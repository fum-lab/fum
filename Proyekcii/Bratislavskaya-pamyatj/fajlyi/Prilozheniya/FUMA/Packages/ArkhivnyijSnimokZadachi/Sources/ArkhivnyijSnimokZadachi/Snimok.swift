func собратьСнимок(_ uuid: String, _ выбор: ВыборФактов, _ граница: ГраницаПрефикса) throws -> Снимок {
    guard let мета = выбор.sessionMeta else { throw ОшибкаАрхива.формат }
    let задача = Задача(поставщик: "codex-jsonl", хост: "архив", идентификатор: uuid)
    var редуктор = try Редуктор(задача: задача)
    func наблюдение(_ поле: Поле, _ значение: String, _ позиция: ПозицияСтроки, _ контекст: String = "") -> Наблюдение {
        let ссылка = "строка:\(позиция.номер);байты:\(позиция.начало)-\(позиция.конец);sha256:\(позиция.sha256)"
        return Наблюдение(идентификатор: поле.rawValue + ":" + позиция.sha256,
            задача: задача, источник: Источник(.журнал, "codex-jsonl:" + мета.позиция.sha256),
            такт: Int64(граница.строки), годноДо: Int64(граница.строки), охват: .частичный,
            область: "записанный-префикс", исходныйФакт: ссылка,
            факт: .значение(поле: поле, контекст: контекст, текст: значение))
    }
    try редуктор.принять(наблюдение(.существует, "да", мета.позиция))
    if let каталог = выбор.каталогRuntime { try редуктор.принять(наблюдение(.каталогRuntime, каталог.значение, каталог.позиция)) }
    if let модель = выбор.модельХода, let ход = выбор.последнийХод {
        try редуктор.принять(наблюдение(.наблюдённаяМодель, модель.значение, модель.позиция, ход.значение))
    }
    return редуктор.снимок
}
func собратьРезультат(_ uuid: String, _ выбор: ВыборФактов, _ граница: ГраницаПрефикса, _ предыдущий: String?) throws -> РезультатАрхива {
    guard let мета = выбор.sessionMeta else { throw ОшибкаАрхива.формат }
    let снимок = try собратьСнимок(uuid, выбор, граница)
    let архив = АрхивноеНаблюдение(версияАдаптера: 1, ожидаемыйUUID: uuid, sessionMeta: мета,
        граница: граница, предыдущийSHA: предыдущий, каталогRuntime: выбор.каталогRuntime,
        последнийХод: выбор.последнийХод, модельХода: выбор.модельХода,
        наблюдения: снимок.наблюдения, shaСнимка: хэшАрхива(try каноническийJSON(снимок)),
        охват: "по состоянию прочитанного префикса")
    return РезультатАрхива(архив: архив, снимок: снимок)
}
func описаниеАрхива(_ архив: АрхивноеНаблюдение) -> ОписаниеНаблюдения {
    ОписаниеНаблюдения(идентификатор: архив.граница.sha256,
        тип: "архивный-снимок-задачи/завершённый-префикс", версияСхемы: 1,
        источник: "codex-jsonl:" + архив.ожидаемыйUUID,
        время: "граница-строк:" + String(архив.граница.строки),
        спецификация: Data("адаптер-1: LF; SHA-256; результат и курсор вместе; частичный охват".utf8))
}
func проверитьХэш(_ строка: String) -> Bool {
    строка.utf8.count == 64 && строка.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
}
func восстановитьРезультат(_ данные: Data, uuid: String, прежний: АрхивноеНаблюдение?, бюджет: БюджетАрхива) throws -> РезультатАрхива {
    guard данные.count <= 65_536 else { throw ОшибкаАрхива.предел }
    let архив: АрхивноеНаблюдение
    do { архив = try JSONDecoder().decode(АрхивноеНаблюдение.self, from: данные) }
    catch { throw ОшибкаАрхива.повреждениеАрхива }
    guard архив.версияАдаптера == 1, архив.ожидаемыйUUID == uuid, архив.sessionMeta.uuid == uuid,
          архив.граница.байты > 0, архив.граница.байты <= бюджет.байты,
          архив.граница.строки > 0, архив.граница.строки <= бюджет.строки,
          проверитьХэш(архив.граница.sha256), проверитьХэш(архив.shaСнимка),
          архив.sessionMeta.позиция.номер == 1, архив.sessionMeta.позиция.начало == 0,
          архив.наблюдения.count <= 3,
          архив.модельХода == nil || архив.последнийХод != nil else { throw ОшибкаАрхива.повреждениеАрхива }
    if let прежний {
        guard архив.sessionMeta == прежний.sessionMeta,
              архив.граница.байты > прежний.граница.байты, архив.граница.строки > прежний.граница.строки,
              архив.предыдущийSHA == хэшАрхива(try каноническийJSON(прежний)) else { throw ОшибкаАрхива.повреждениеАрхива }
        guard прежний.каталогRuntime == nil || архив.каталогRuntime != nil,
              прежний.последнийХод == nil || архив.последнийХод != nil else { throw ОшибкаАрхива.повреждениеАрхива }
        for (факт, старый) in [(архив.каталогRuntime, прежний.каталогRuntime),
                               (архив.последнийХод, прежний.последнийХод), (архив.модельХода, прежний.модельХода)] {
            if let факт, факт.позиция.номер <= прежний.граница.строки {
                guard let старый, try каноническийJSON(факт) == каноническийJSON(старый) else { throw ОшибкаАрхива.повреждениеАрхива }
            }
        }
        if let модель = архив.модельХода, модель.позиция.номер <= прежний.граница.строки {
            guard let ход = архив.последнийХод, let старый = прежний.последнийХод,
                  ход.значение.utf8.elementsEqual(старый.значение.utf8) else { throw ОшибкаАрхива.повреждениеАрхива }
        }
    } else if архив.предыдущийSHA != nil { throw ОшибкаАрхива.повреждениеАрхива }
    for (факт, предел) in [(архив.каталогRuntime, 1024), (архив.последнийХод, 128), (архив.модельХода, 128)] {
        if let факт { _ = try строковоеПоле(["значение": факт.значение], "значение", предел: предел) }
    }
    let позиции = [архив.sessionMeta.позиция] + [архив.каталогRuntime?.позиция, архив.последнийХод?.позиция, архив.модельХода?.позиция].compactMap { $0 }
    for позиция in позиции {
        guard позиция.номер > 0, позиция.номер <= архив.граница.строки,
              позиция.начало >= 0, позиция.конец > позиция.начало,
              позиция.конец <= архив.граница.байты, позиция.конец - позиция.начало <= бюджет.строка,
              проверитьХэш(позиция.sha256) else { throw ОшибкаАрхива.повреждениеАрхива }
        if позиция.номер == архив.граница.строки, позиция.конец != архив.граница.байты { throw ОшибкаАрхива.повреждениеАрхива }
    }
    let упорядоченные = позиции.sorted { $0.номер < $1.номер }
    for место in 1..<упорядоченные.count {
        let до = упорядоченные[место - 1]; let после = упорядоченные[место]
        guard до.номер == после.номер ? до == после : до.конец <= после.начало else { throw ОшибкаАрхива.повреждениеАрхива }
    }
    // Каждая точка связывает число завершённых LF-строк с точным смещением.
    // Минимум session_meta с UUID — 80 байтов; нейтральная строка — 34 с LF.
    guard архив.sessionMeta.позиция.конец >= 80 else { throw ОшибкаАрхива.повреждениеАрхива }
    var точки = [(строки: 0, байты: 0), (строки: архив.граница.строки, байты: архив.граница.байты)]
    for позиция in позиции {
        точки.append((строки: позиция.номер - 1, байты: позиция.начало))
        точки.append((строки: позиция.номер, байты: позиция.конец))
    }
    if let прежний { точки.append((строки: прежний.граница.строки, байты: прежний.граница.байты)) }
    точки.sort { $0.строки < $1.строки }
    for место in 1..<точки.count {
        let до = точки[место - 1]; let после = точки[место]
        let строки = после.строки - до.строки
        let байты = после.байты - до.байты
        if строки == 0 {
            guard байты == 0 else { throw ОшибкаАрхива.повреждениеАрхива }
        } else {
            let (минимум, нижнееПереполнение) = строки.multipliedReportingOverflow(by: 34)
            let (максимум, верхнееПереполнение) = строки.multipliedReportingOverflow(by: бюджет.строка)
            guard !нижнееПереполнение, !верхнееПереполнение, байты >= минимум, байты <= максимум else {
                throw ОшибкаАрхива.повреждениеАрхива
            }
        }
    }
    if let ход = архив.последнийХод {
        guard ход.позиция.номер > 1 else { throw ОшибкаАрхива.повреждениеАрхива }
        if let модель = архив.модельХода {
            guard модель.позиция.номер > 1, модель.позиция.номер <= ход.позиция.номер else { throw ОшибкаАрхива.повреждениеАрхива }
        }
    }
    let выбор = ВыборФактов(sessionMeta: архив.sessionMeta, каталогRuntime: архив.каталогRuntime,
                           последнийХод: архив.последнийХод, модельХода: архив.модельХода)
    let результат = try собратьРезультат(uuid, выбор, архив.граница, архив.предыдущийSHA)
    guard try каноническийJSON(результат.архив) == данные else { throw ОшибкаАрхива.повреждениеАрхива }
    return результат
}
public func архивныйMarkdown(_ результат: РезультатАрхива) -> String {
    func безопасно(_ строка: String) -> String {
        строка.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "`", with: "&#96;")
    }
    let архив = результат.архив
    return """
    # Архивный снимок записанной задачи

    Частичный охват: по состоянию прочитанного префикса.

    - UUID записанной сессии: \(архив.ожидаемыйUUID).
    - Завершённый префикс: \(архив.граница.байты) байтов, \(архив.граница.строки) строк.
    - SHA-256 префикса: \(архив.граница.sha256).
    - Явно записанный runtime cwd: `\(безопасно(архив.каталогRuntime?.значение ?? "неизвестно"))`.
    - Последний явно идентифицированный ход: `\(безопасно(архив.последнийХод?.значение ?? "неизвестно"))`.
    - Модель этого хода: `\(безопасно(архив.модельХода?.значение ?? "неизвестно"))`.

    Завершение задачи, выполнение обязательств, ожидание человека, активность процесса,
    назначенное рабочее дерево и эффекты интерфейса неизвестны.
    EOF, тишина, final-ответ и HookPrompt этих состояний не доказывают.
    Существование относится к записи сессии в архиве, а не к живому процессу.
    Источник не нужен для replay; следующий импорт требует проверки принятого префикса.
    """ + "\n"
}

import Foundation

public func примерСценария() -> Сценарий {
    let задача = Задача(поставщик: "синтетический-codex", хост: "стенд", идентификатор: "задача-1")
    var наблюдения: [Наблюдение] = []
    func добавить(_ факт: Факт, _ канал: Канал = .журнал, _ охват: Охват = .точечный,
                  годноДо: Int64 = 100) {
        let номер = наблюдения.count + 1
        наблюдения.append(Наблюдение(идентификатор: "пример-\(номер)", задача: задача,
            источник: Источник(канал), такт: Int64(номер), годноДо: годноДо, охват: охват,
            область: "синтетическая-вкладка-1", исходныйФакт: "Записанный синтетический факт №\(номер)", факт: факт))
    }
    добавить(.значение(поле: .существует, контекст: "", текст: "да"))
    добавить(.список(задачи: []), .api, .частичный)
    добавить(.значение(поле: .желаемаяМодель, контекст: "", текст: "модель-А"), .настройка)
    добавить(.значение(поле: .наблюдённаяМодель, контекст: "ход-1", текст: "модель-Б"))
    добавить(.значение(поле: .каталогRuntime, контекст: "", текст: "/синтетика/runtime"))
    добавить(.значение(поле: .каталогКоманды, контекст: "команда-1", текст: "/синтетика/команда"), .команда)
    добавить(.значение(поле: .назначенныйWorktree, контекст: "", текст: "/синтетика/назначение"), .настройка)
    добавить(.значение(поле: .текущаяРабота, контекст: "", текст: "сборка"), годноДо: 9)
    добавить(.значение(поле: .текущаяРабота, контекст: "", текст: "проверка"), .api, годноДо: 9)
    добавить(.значение(поле: .ожидание, контекст: "", текст: "полномочия"))
    добавить(.расхождение(ожидалось: "выбрана задача-1", наблюдалось: "выбрана задача-2"), .интерфейс)
    добавить(.команда(операция: "исправление-1", фаза: .отправлена, эффект: "выбрана задача-1", корректирует: "пример-11"), .команда)
    добавить(.эффект(операция: "исправление-1", текст: "выбрана задача-1"), .интерфейс)
    добавить(.команда(операция: "неподтверждённая-2", фаза: .отправлена, эффект: "открыта панель", корректирует: nil), .команда)
    добавить(.команда(операция: "неподтверждённая-2", фаза: .принята, эффект: "открыта панель", корректирует: nil), .команда)
    добавить(.отказ(причина: "синтетический отказ полномочий; обход запрещён"), .интерфейс)
    добавить(.эффект(операция: "неподтверждённая-2", текст: "открыта панель"), .интерфейс)
    добавить(.время)
    return Сценарий(задача: задача, наблюдения: наблюдения)
}

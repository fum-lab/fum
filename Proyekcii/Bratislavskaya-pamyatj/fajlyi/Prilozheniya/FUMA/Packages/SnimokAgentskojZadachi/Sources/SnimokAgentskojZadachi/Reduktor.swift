import Foundation

public struct Редуктор: Sendable {
    public private(set) var снимок: Снимок
    public init(задача: Задача) throws {
        try проверитьЗадачу(задача)
        снимок = Снимок(версия: 1, задача: задача.нормализованнаяИдентичность, такт: 0, поля: [], неизвестныеПоля: Поле.allCases,
                        недоступныеКаналы: [], разрывыОхвата: [], проигнорированы: [],
                        операции: [], последняяПодтверждённаяКорректировка: nil, наблюдения: [])
    }
    public mutating func принять(_ наблюдение: Наблюдение) throws {
        try проверитьНаблюдение(наблюдение)
        guard наблюдение.задача == снимок.задача else { throw ОшибкаСнимка.чужаяЗадача }
        if let прежнее = снимок.наблюдения.first(where: { $0.идентификатор == наблюдение.идентификатор }) {
            guard try каноническийJSON(прежнее) == каноническийJSON(наблюдение) else {
                throw ОшибкаСнимка.конфликтИдентификатора
            }
            return
        }
        guard снимок.наблюдения.count < БюджетСнимка.наблюдения else { throw ОшибкаСнимка.предел }
        // Такт — единые логические часы сценария, не часы реальных источников.
        guard наблюдение.такт >= снимок.такт else { throw ОшибкаСнимка.неверныйВвод }
        let наблюдения = снимок.наблюдения + [наблюдение]
        guard Set(наблюдения.map(\.источник)).count <= 8 else { throw ОшибкаСнимка.предел }
        var поля = снимок.поля
        var недоступные = снимок.недоступныеКаналы
        var разрывы = снимок.разрывыОхвата
        var проигнорированы = снимок.проигнорированы
        var операции = снимок.операции
        var корректировка = снимок.последняяПодтверждённаяКорректировка

        func добавить(_ поле: Поле, _ контекст: String, _ текст: String) {
            let прежние = поля.first { $0.поле == поле && $0.контекст == контекст }?.кандидаты ?? []
            let кандидаты = прежние.filter { !наблюдение.заменяет.contains($0.свидетельство) }
                + [Кандидат(значение: текст, свидетельство: наблюдение.идентификатор, устарело: false)]
            поля.removeAll { $0.поле == поле && $0.контекст == контекст }
            поля.append(ЗначениеПоля(поле: поле, контекст: контекст, знание: .согласовано, кандидаты: кандидаты))
        }

        if недоступные.contains(where: { $0.источник.канал == наблюдение.источник.канал }) {
            проигнорированы.append(наблюдение.идентификатор)
        } else {
            switch наблюдение.факт {
            case let .значение(поле, контекст, текст):
                for ссылка in наблюдение.заменяет {
                    guard let прежнее = снимок.наблюдения.first(where: { $0.идентификатор == ссылка }),
                          прежнее.источник == наблюдение.источник, прежнее.область == наблюдение.область,
                          case let .значение(староеПоле, старыйКонтекст, _) = прежнее.факт,
                          староеПоле == поле, старыйКонтекст == контекст,
                          снимок.значение(поле, контекст).кандидаты.contains(where: { $0.свидетельство == ссылка }) else {
                        throw ОшибкаСнимка.неверныйВвод
                    }
                }
                добавить(поле, контекст, текст)
            case let .список(задачи):
                if задачи.contains(снимок.задача) { добавить(.существует, "", "да") }
                else { разрывы.append(наблюдение.идентификатор) }
            case let .отказ(причина):
                недоступные.append(НедоступныйКанал(источник: наблюдение.источник,
                    причина: причина, свидетельство: наблюдение.идентификатор))
            case .расхождение: break
            case let .команда(идентификатор, фаза, эффект, ссылка):
                let уровни: [ФазаКоманды: Int] = [.намерение: 0, .отправлена: 1, .принята: 2]
                if let место = операции.firstIndex(where: { $0.идентификатор == идентификатор }) {
                    let прежняя = операции[место]
                    guard let начало = снимок.наблюдения.first(where: {
                              $0.идентификатор == прежняя.свидетельстваКоманды.first
                          }), начало.область == наблюдение.область, начало.источник == наблюдение.источник,
                          прежняя.ожидаемыйЭффект == эффект, прежняя.корректирует == ссылка,
                          прежняя.подтверждение == nil,
                          уровни[фаза]! >= уровни[прежняя.фаза]!,
                          уровни[фаза]! <= уровни[прежняя.фаза]! + 1 else { throw ОшибкаСнимка.неверныйВвод }
                    операции[место].фаза = фаза
                    операции[место].свидетельстваКоманды.append(наблюдение.идентификатор)
                } else {
                    guard фаза != .принята, операции.count < 16 else { throw ОшибкаСнимка.неверныйВвод }
                    if let ссылка {
                        guard let причина = снимок.наблюдения.first(where: { $0.идентификатор == ссылка }),
                              case let .расхождение(ожидалось, _) = причина.факт,
                              ожидалось == эффект, причина.область == наблюдение.область,
                              причина.такт < наблюдение.такт,
                              !снимок.проигнорированы.contains(ссылка) else { throw ОшибкаСнимка.неверныйВвод }
                    }
                    операции.append(Операция(идентификатор: идентификатор, фаза: фаза,
                        ожидаемыйЭффект: эффект, корректирует: ссылка,
                        свидетельстваКоманды: [наблюдение.идентификатор], подтверждение: nil))
                }
            case let .эффект(идентификатор, текст):
                guard let место = операции.firstIndex(where: { $0.идентификатор == идентификатор }),
                      операции[место].фаза != .намерение,
                      операции[место].ожидаемыйЭффект == текст,
                      операции[место].подтверждение == nil,
                      let команда = снимок.наблюдения.first(where: {
                          $0.идентификатор == операции[место].свидетельстваКоманды.last
                      }),
                      наблюдение.область == команда.область,
                      наблюдение.такт > команда.такт else { throw ОшибкаСнимка.неподтверждаемыйЭффект }
                операции[место].подтверждение = наблюдение.идентификатор
                if операции[место].корректирует != nil { корректировка = идентификатор }
            case .время: break
            }
        }
        let поИдентификатору = Dictionary(uniqueKeysWithValues: наблюдения.map { ($0.идентификатор, $0) })
        поля = поля.map { поле in
            let кандидаты = поле.кандидаты.map {
                Кандидат(значение: $0.значение, свидетельство: $0.свидетельство,
                         устарело: поИдентификатору[$0.свидетельство]!.годноДо < наблюдение.такт)
            }
            return ЗначениеПоля(поле: поле.поле, контекст: поле.контекст,
                знание: Set(кандидаты.map(\.значение)).count > 1 ? .противоречие : .согласовано,
                кандидаты: кандидаты)
        }.sorted { ($0.поле.rawValue, $0.контекст) < ($1.поле.rawValue, $1.контекст) }
        guard поля.count <= 64 else { throw ОшибкаСнимка.предел }
        снимок = Снимок(версия: 1, задача: снимок.задача, такт: наблюдение.такт, поля: поля,
                        неизвестныеПоля: Поле.allCases.filter { поле in !поля.contains { $0.поле == поле } },
                        недоступныеКаналы: недоступные, разрывыОхвата: разрывы, проигнорированы: проигнорированы,
                        операции: операции, последняяПодтверждённаяКорректировка: корректировка, наблюдения: наблюдения)
    }
}

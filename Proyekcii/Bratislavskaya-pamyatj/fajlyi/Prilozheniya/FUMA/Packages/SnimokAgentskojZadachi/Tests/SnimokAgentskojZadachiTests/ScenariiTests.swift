import Foundation
import XCTest
@testable import СнимокАгентскойЗадачи

let задачаПримера = Задача(поставщик: "синтетический-codex", хост: "стенд", идентификатор: "задача-1")

func запись(_ номер: Int, _ факт: Факт, канал: Канал = .журнал,
            охват: Охват = .точечный, заменяет: [String] = [],
            годноДо: Int64 = 100) -> Наблюдение {
    Наблюдение(идентификатор: "н-\(номер)", задача: задачаПримера,
               источник: Источник(канал), такт: Int64(номер), годноДо: годноДо,
               охват: охват, заменяет: заменяет, факт: факт)
}
func свернуть(_ записи: [Наблюдение]) throws -> Снимок {
    var редуктор = try Редуктор(задача: задачаПримера)
    for запись in записи { try редуктор.принять(запись) }
    return редуктор.снимок
}

final class СценарииTests: XCTestCase {
    func testНеполныйAPIНеДоказываетОтсутствие() throws {
        let снимок = try свернуть([
            запись(1, .значение(поле: .существует, контекст: "", текст: "да")),
            запись(2, .список(задачи: []), канал: .api, охват: .частичный)
        ])
        XCTAssertEqual(снимок.значение(.существует).знание, .согласовано)
        XCTAssertEqual(снимок.значение(.существует).кандидаты.map(\.значение), ["да"])
        XCTAssertEqual(снимок.разрывыОхвата, ["н-2"])
    }
    func testВыбраннаяМодельНеПодменяетНаблюдённуюМодельХода() throws {
        let снимок = try свернуть([
            запись(1, .значение(поле: .желаемаяМодель, контекст: "", текст: "модель-А"), канал: .настройка),
            запись(2, .значение(поле: .наблюдённаяМодель, контекст: "ход-1", текст: "модель-Б"))
        ])
        XCTAssertEqual(снимок.значение(.желаемаяМодель).кандидаты.map(\.значение), ["модель-А"])
        XCTAssertEqual(снимок.значение(.наблюдённаяМодель, "ход-1").кандидаты.map(\.значение), ["модель-Б"])
        XCTAssertEqual(снимок.значение(.наблюдённаяМодель, "ход-2").знание, .неизвестно)
    }
    func testКаталогКомандыНеМеняетRuntimeИВладениеWorktree() throws {
        let снимок = try свернуть([
            запись(1, .значение(поле: .каталогRuntime, контекст: "", текст: "/синтетика/runtime")),
            запись(2, .значение(поле: .каталогКоманды, контекст: "команда-1", текст: "/синтетика/другое"), канал: .команда),
            запись(3, .значение(поле: .назначенныйWorktree, контекст: "", текст: "/синтетика/назначенное"), канал: .настройка)
        ])
        XCTAssertEqual(снимок.значение(.каталогRuntime).кандидаты.map(\.значение), ["/синтетика/runtime"])
        XCTAssertEqual(снимок.значение(.каталогКоманды, "команда-1").кандидаты.map(\.значение), ["/синтетика/другое"])
        XCTAssertEqual(снимок.значение(.назначенныйWorktree).кандидаты.map(\.значение), ["/синтетика/назначенное"])
    }
    func testОтправкаИПринятиеНеПодтверждаютЭффект() throws {
        let снимок = try свернуть([
            запись(1, .команда(операция: "операция-1", фаза: .отправлена, эффект: "открыта-задача-1", корректирует: nil), канал: .команда),
            запись(2, .команда(операция: "операция-1", фаза: .принята, эффект: "открыта-задача-1", корректирует: nil), канал: .команда)
        ])
        XCTAssertEqual(снимок.операции.count, 1)
        XCTAssertEqual(снимок.операции.first?.фаза, .принята)
        XCTAssertNil(снимок.операции.first?.подтверждение)
        XCTAssertNil(снимок.последняяПодтверждённаяКорректировка)
    }
    func testОтказКаналаНеОбходитсяИНеСтираетДругиеИсточники() throws {
        let снимок = try свернуть([
            запись(1, .отказ(причина: "нет полномочий"), канал: .интерфейс),
            запись(2, .значение(поле: .текущаяРабота, контекст: "", текст: "невозможное UI"), канал: .интерфейс),
            запись(3, .значение(поле: .текущаяРабота, контекст: "", текст: "синтетическая сборка"))
        ])
        XCTAssertEqual(снимок.недоступныеКаналы.count, 1)
        XCTAssertEqual(снимок.проигнорированы, ["н-2"])
        XCTAssertEqual(снимок.значение(.текущаяРабота).кандидаты.map(\.значение), ["синтетическая сборка"])
    }
}

import Foundation
import CryptoKit

let сигнатура = Data("FUMOBS01".utf8)

func хэш(_ данные: Data) -> Data { Data(SHA256.hash(data: данные)) }
func строкаХэша(_ данные: Data) -> String { данные.map { String(format: "%02x", $0) }.joined() }

func кодировать<Значение: Encodable>(_ значение: Значение) throws -> Data {
    let кодировщик = JSONEncoder(); кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
    let байты = try кодировщик.encode(значение)
    guard байты.count <= Пределы.заголовок else { throw ОшибкаКонтейнера.предел }
    return байты
}

func декодировать<Значение: Codable>(_ тип: Значение.Type, _ байты: Data) throws -> Значение {
    do {
        let значение = try JSONDecoder().decode(тип, from: байты)
        // Формат v1 требует канонический JSON; дубли, лишние поля и неоднозначные числа отклоняются.
        guard try кодировать(значение) == байты else { throw ОшибкаКонтейнера.повреждение }
        return значение
    } catch { throw ОшибкаКонтейнера.повреждение }
}

func проверитьОписание(_ описание: ОписаниеНаблюдения) throws {
    guard !описание.идентификатор.isEmpty, описание.идентификатор.utf8.count <= 256,
          !описание.тип.isEmpty, описание.тип.utf8.count <= 1024,
          !описание.источник.isEmpty, описание.источник.utf8.count <= 1024,
          !описание.время.isEmpty, описание.время.utf8.count <= 128,
          описание.версияСхемы > 0, !описание.спецификация.isEmpty,
          описание.спецификация.count <= 65_536 else { throw ОшибкаКонтейнера.предел }
}

func число(_ данные: Data, _ начало: Int, _ ширина: Int) -> UInt64 {
    данные[начало..<(начало + ширина)].reduce(0) { ($0 << 8) | UInt64($1) }
}

func байтыЧисла(_ значение: UInt64, _ ширина: Int) -> Data {
    Data((0..<ширина).reversed().map { UInt8(truncatingIfNeeded: значение >> ($0 * 8)) })
}

struct Фрагмент: Codable { let номер: Int; let смещение: UInt64 }
struct Фиксация: Codable { let размер: UInt64; let фрагменты: Int; let хэш: String }
struct Участок { let начало: Int; let длина: Int; let хэш: Data }
struct Группа { let квитанция: Квитанция; let участки: [Участок] }

struct Снимок {
    var группы: [Группа] = []
    var конец = сигнатура.count
    var следующийНомер: UInt64 = 0
    var предыдущийХэш = хэш(сигнатура)
    var хвост = false
}

func сканировать(_ дескриптор: Int32) throws -> Снимок {
    let размер = try размерФайла(дескриптор)
    guard размер >= сигнатура.count, try прочитать(дескриптор, 0, сигнатура.count) == сигнатура else {
        throw ОшибкаКонтейнера.повреждение
    }
    var снимок = Снимок()
    var позиция = сигнатура.count
    var номер: UInt64 = 0
    var предыдущий = хэш(сигнатура)
    var описание: ОписаниеНаблюдения?
    var участки: [Участок] = []
    var размерОбъекта: UInt64 = 0
    var хэшОбъекта = SHA256()
    var идентификаторы = Set<String>()
    var всегоФрагментов = 0
    while позиция < размер {
        // Префикс: 24 байта полей + 32 байта SHA-256 этих полей.
        guard размер - позиция >= 56 else { снимок.хвост = true; return снимок }
        let префикс = try прочитать(дескриптор, позиция, 24)
        guard try прочитать(дескриптор, позиция + 24, 32) == хэш(префикс),
              префикс.prefix(4) == Data("OBS1".utf8),
              префикс[5..<8] == Data(repeating: 0, count: 3),
              число(префикс, 16, 8) == номер else { throw ОшибкаКонтейнера.повреждение }
        let длинаЗаголовка = Int(число(префикс, 8, 4))
        let длинаДанных = Int(число(префикс, 12, 4))
        guard длинаЗаголовка > 0, длинаЗаголовка <= Пределы.заголовок,
              длинаДанных <= Пределы.фрагмент else { throw ОшибкаКонтейнера.предел }
        let полнаяДлина = 56 + длинаЗаголовка + длинаДанных + 32
        // Все доступные по префиксу ограничения проверяются до allocation payload.
        switch префикс[4] {
        case 1:
            guard описание == nil, длинаДанных == 0 else { throw ОшибкаКонтейнера.повреждение }
            guard снимок.группы.count < Пределы.записи else { throw ОшибкаКонтейнера.предел }
        case 2:
            guard описание != nil, длинаДанных > 0 else { throw ОшибкаКонтейнера.повреждение }
            guard размерОбъекта <= Пределы.объект - UInt64(длинаДанных),
                  всегоФрагментов < Пределы.фрагменты else { throw ОшибкаКонтейнера.предел }
        case 3:
            guard описание != nil, длинаДанных == 0 else { throw ОшибкаКонтейнера.повреждение }
        default: throw ОшибкаКонтейнера.повреждение
        }
        guard размер - позиция >= полнаяДлина else { снимок.хвост = true; return снимок }
        let заголовок = try прочитать(дескриптор, позиция + 56, длинаЗаголовка)
        let началоДанных = позиция + 56 + длинаЗаголовка
        let данные = try прочитать(дескриптор, началоДанных, длинаДанных)
        var счётчик = SHA256(); счётчик.update(data: предыдущий); счётчик.update(data: префикс)
        счётчик.update(data: заголовок); счётчик.update(data: данные)
        let следующийХэш = Data(счётчик.finalize())
        guard try прочитать(дескриптор, позиция + полнаяДлина - 32, 32) == следующийХэш else {
            throw ОшибкаКонтейнера.повреждение
        }
        switch префикс[4] {
        case 1:
            guard описание == nil, длинаДанных == 0, снимок.группы.count < Пределы.записи else {
                throw ОшибкаКонтейнера.повреждение
            }
            let новое = try декодировать(ОписаниеНаблюдения.self, заголовок)
            try проверитьОписание(новое)
            guard !идентификаторы.contains(новое.идентификатор) else { throw ОшибкаКонтейнера.повреждение }
            описание = новое; участки = []; размерОбъекта = 0; хэшОбъекта = SHA256()
        case 2:
            let фрагмент = try декодировать(Фрагмент.self, заголовок)
            guard описание != nil, длинаДанных > 0, фрагмент.номер == участки.count,
                  фрагмент.смещение == размерОбъекта else { throw ОшибкаКонтейнера.повреждение }
            guard размерОбъекта <= Пределы.объект - UInt64(длинаДанных),
                  всегоФрагментов < Пределы.фрагменты else { throw ОшибкаКонтейнера.предел }
            хэшОбъекта.update(data: данные); размерОбъекта += UInt64(длинаДанных); всегоФрагментов += 1
            участки.append(Участок(начало: началоДанных, длина: длинаДанных, хэш: хэш(данные)))
        case 3:
            let фиксация = try декодировать(Фиксация.self, заголовок)
            guard let описание, длинаДанных == 0, фиксация.размер == размерОбъекта,
                  фиксация.фрагменты == участки.count,
                  фиксация.хэш == строкаХэша(Data(хэшОбъекта.finalize())) else {
                throw ОшибкаКонтейнера.повреждение
            }
            let квитанция = Квитанция(описание: описание, размер: размерОбъекта, хэш: фиксация.хэш)
            снимок.группы.append(Группа(квитанция: квитанция, участки: участки))
            идентификаторы.insert(описание.идентификатор)
            снимок.конец = позиция + полнаяДлина; снимок.следующийНомер = номер + 1
            снимок.предыдущийХэш = следующийХэш
        default: throw ОшибкаКонтейнера.повреждение
        }
        if префикс[4] == 3 { описание = nil }
        позиция += полнаяДлина; номер += 1; предыдущий = следующийХэш
    }
    снимок.хвост = описание != nil
    return снимок
}

    @Test(arguments: [false, true])
    func повторПослеНеясногоSyncТребуетУспешныйSync(отказатьКаталогу: Bool) throws {
        let путь = try корень(); defer { try? FileManager.default.removeItem(at: путь) }
        try Сегмент(кореньДанных: путь, запись: true).закрыть()
        let описание = ОписаниеНаблюдения(идентификатор: "неясный", тип: "сырой/будущий")
        let данные = Data([0, 255, 42])
        let операции = ФайловыеОперации(запись: ФайловыеОперации.системные.запись, синхронизация: { дескриптор in
            var сведения = stat()
            guard fstat(дескриптор, &сведения) == 0 else { throw ОшибкаКонтейнера.система(errno) }
            if !отказатьКаталогу || сведения.st_mode & S_IFMT == S_IFDIR {
                throw ОшибкаКонтейнера.система(EIO)
            }
            try ФайловыеОперации.системные.синхронизация(дескриптор)
        })
        let писатель = try Сегмент(кореньДанных: путь, запись: true, операции: операции)
        #expect(throws: ОшибкаКонтейнера.система(EIO)) { try писатель.добавить(описание, данные: данные) }
        #expect(писатель.записи.isEmpty)
        #expect(throws: ОшибкаКонтейнера.закрыт) { try писатель.добавить(описание, данные: данные) }
        писатель.закрыть()
        let файл = путь.appendingPathComponent("сегмент.fumobs")
        let видимые = try Data(contentsOf: файл)
        let повтор = try Сегмент(кореньДанных: путь, запись: true, операции: операции)
        #expect(повтор.записи.count == 1) // commit виден, но подтверждать пока нельзя.
        #expect(throws: ОшибкаКонтейнера.система(EIO)) { try повтор.добавить(описание, данные: данные) }
        повтор.закрыть()
        #expect(try Data(contentsOf: файл) == видимые)
        let успешный = try Сегмент(кореньДанных: путь, запись: true, профилировать: true)
        let квитанция = try успешный.добавить(описание, данные: данные)
        #expect(квитанция.размер == данные.count)
        #expect(успешный.профиль.contains { $0.этап == "синхронизация-файла" && $0.исход == "успешно" })
        #expect(успешный.профиль.contains { $0.этап == "синхронизация-каталога" && $0.исход == "успешно" })
        успешный.закрыть()
        #expect(try Data(contentsOf: файл) == видимые)
    }


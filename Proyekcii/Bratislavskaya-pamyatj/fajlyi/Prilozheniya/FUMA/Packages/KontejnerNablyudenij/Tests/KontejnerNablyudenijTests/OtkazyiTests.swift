final class СчётчикВызовов: @unchecked Sendable {
    private let замок = NSLock()
    private var число = 0
    func следующий() -> Int {
        замок.lock(); defer { замок.unlock() }
        число += 1; return число
    }
}

final class ДубликатыДескрипторов: @unchecked Sendable {
    private let замок = NSLock()
    private var список: [Int32] = []
    func сохранить(_ fd: Int32) throws {
        замок.lock(); defer { замок.unlock() }
        let копия = fcntl(fd, F_DUPFD_CLOEXEC, 0)
        guard копия >= 0 else { throw ОшибкаКонтейнера.система(errno) }
        список.append(копия)
    }
    deinit { for fd in список { _ = Darwin.close(fd) } }
}


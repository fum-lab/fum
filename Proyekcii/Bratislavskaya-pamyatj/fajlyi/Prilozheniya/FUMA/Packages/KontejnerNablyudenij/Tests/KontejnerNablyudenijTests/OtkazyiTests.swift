    @Test func сигналПовторяетсяИПолныйWriteПредшествуетОбоимSync() throws {
        let путь = try корень(); defer { try? FileManager.default.removeItem(at: путь) }
        try Сегмент(кореньДанных: путь, запись: true).закрыть()
        let записи = СчётчикВызовов(), синхронизации = СчётчикВызовов()
        let операции = ФайловыеОперации(запись: { дескриптор, буфер in
            if записи.следующий() == 1 { throw ОшибкаКонтейнера.система(EINTR) }
            return try ФайловыеОперации.системные.запись(дескриптор, UnsafeRawBufferPointer(rebasing: буфер.prefix(7)))
        }, синхронизация: { дескриптор in
            if синхронизации.следующий() == 1 { throw ОшибкаКонтейнера.система(EINTR) }
            var сведения = stat(); #expect(fstat(дескриптор, &сведения) == 0)
            if сведения.st_mode & S_IFMT == S_IFREG { #expect(try сканировать(дескриптор).группы.count == 1) }
            try ФайловыеОперации.системные.синхронизация(дескриптор)
        })
        let писатель = try Сегмент(кореньДанных: путь, запись: true, операции: операции)
        _ = try писатель.добавить(ОписаниеНаблюдения(идентификатор: "сигнал", тип: "байты"), данные: Data(repeating: 7, count: 400))
        #expect(синхронизации.следующий() == 4) // EINTR, file success, directory success.
    }

    @Test(arguments: [true, false])
    func частичныйОтказОставляетТолькоВосстанавливаемыйХвост(нулевойWrite: Bool) throws {
        let путь = try корень(); defer { try? FileManager.default.removeItem(at: путь) }
        let первый = try Сегмент(кореньДанных: путь, запись: true)
        _ = try первый.добавить(ОписаниеНаблюдения(идентификатор: "до", тип: "байты"), данные: Data([1]))
        первый.закрыть()
        let файл = путь.appendingPathComponent("сегмент.fumobs")
        let префикс = try Data(contentsOf: файл)
        let вызовы = СчётчикВызовов()
        let операции = ФайловыеОперации(запись: { дескриптор, буфер in
            if вызовы.следующий() > 1 {
                if нулевойWrite { return 0 }
                throw ОшибкаКонтейнера.система(ENOSPC)
            }
            return try ФайловыеОперации.системные.запись(дескриптор, буфер)
        }, синхронизация: ФайловыеОперации.системные.синхронизация)
        let писатель = try Сегмент(кореньДанных: путь, запись: true, операции: операции)
        #expect(throws: ОшибкаКонтейнера.система(нулевойWrite ? EIO : ENOSPC)) {
            try писатель.добавить(ОписаниеНаблюдения(идентификатор: "после", тип: "байты"), данные: Data([2]))
        }
        писатель.закрыть()
        let восстановитель = try Сегмент(кореньДанных: путь, запись: true)
        #expect(восстановитель.естьХвост)
        try восстановитель.восстановитьХвост()
        #expect(try Data(contentsOf: файл) == префикс)
    }

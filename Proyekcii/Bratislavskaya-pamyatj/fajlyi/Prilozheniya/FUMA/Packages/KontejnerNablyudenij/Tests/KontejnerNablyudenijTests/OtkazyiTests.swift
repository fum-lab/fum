    @Test func обнаруженноеПовреждениеБлокируетЗапись() throws {
        let путь = try корень(); defer { try? FileManager.default.removeItem(at: путь) }
        let писатель = try Сегмент(кореньДанных: путь, запись: true)
        _ = try писатель.добавить(ОписаниеНаблюдения(идентификатор: "до", тип: "байты"), данные: Data([7]))
        let файл = путь.appendingPathComponent("сегмент.fumobs")
        var байты = try Data(contentsOf: файл)
        let второйКадр = 8 + 88 + Int(число(байты, 16, 4))
        let началоДанных = второйКадр + 56 + Int(число(байты, второйКадр + 8, 4))
        байты[началоДанных] ^= 1
        // Моделируем повреждение носителя, сознательно минуя advisory lock.
        let дескриптор = open(файл.path, O_WRONLY | O_CLOEXEC)
        defer { _ = close(дескриптор) }
        #expect(байты.withUnsafeBytes { pwrite(дескриптор, $0.baseAddress, $0.count, 0) } == байты.count)
        #expect(throws: ОшибкаКонтейнера.повреждение) { try писатель.извлечь("до") }
        #expect(throws: ОшибкаКонтейнера.закрыт) {
            try писатель.добавить(ОписаниеНаблюдения(идентификатор: "после", тип: "байты"), данные: Data([1]))
        }
        #expect(try Data(contentsOf: файл) == байты)
    }


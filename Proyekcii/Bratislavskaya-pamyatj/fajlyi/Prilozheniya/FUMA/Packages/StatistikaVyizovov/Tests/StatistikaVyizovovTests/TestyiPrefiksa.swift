import Foundation
import XCTest
@testable import СтатистикаВызовов

final class ТестыПрефикса: XCTestCase {
    func testДваНастоящихВызоваОдногоИнструментаНеСхлопываются() throws {
        let данные = try метаданные() + вызов() + результат() + вызов("call_b", произвольный: true) + результат("call_b", произвольный: true)
        let отчёт = try сводка(данные)
        XCTAssertEqual(отчёт.прямыхВызовов, 2)
        XCTAssertEqual(отчёт.сопряжённыхРезультатов, 2)
        XCTAssertEqual(отчёт.вызовы.map(\.задержкаНаносекунды), [250_000_000, 250_000_000])
        XCTAssertEqual(отчёт.инструменты.first?.прямыхВызовов, 2)
        XCTAssertEqual(отчёт.граница?.байт, данные.count)
    }
    func testТочныеДублиСохраняютПроисхождениеНеСчётчики() throws {
        let данные = try метаданные() + вызов() + результат() + вызов() + результат()
        let отчёт = try сводка(данные)
        XCTAssertEqual(отчёт.прямыхВызовов, 1)
        XCTAssertEqual(отчёт.сопряжённыхРезультатов, 1)
        XCTAssertEqual(отчёт.дубликатов, 2)
        XCTAssertEqual(отчёт.граница?.строк, 5)
    }
    func test_НепарныйИПустойРезультатНеНовыеВызовы() throws {
        let отчёт = try сводка(метаданные() + вызов() + результат("orphan") + результат(NSNull()))
        XCTAssertEqual(отчёт.прямыхВызовов, 1)
        XCTAssertEqual(отчёт.несопряжённыхРезультатов, 2)
        XCTAssertEqual(отчёт.сопряжённыхРезультатов, 0)
        XCTAssertEqual(отчёт.вызовы.first?.связь, .отсутствует)
    }
    func testНеверноеВремяИОтсутствующееНеВыдумываются() throws {
        let отчёт = try сводка(метаданные() + вызов(время: nil) + результат() +
            вызов("call_b", время: "2026-02-30T12:00:00Z") + результат("call_b"))
        XCTAssertEqual(отчёт.вызовы.map { $0.вызов.момент.качество }, [.отсутствует, .неверно])
        XCTAssertTrue(отчёт.вызовы.allSatisfy { $0.задержкаНаносекунды == nil })
        XCTAssertEqual(отчёт.сопряжённыхРезультатов, 2)
    }
    func testНевернаяИОтсутствующаяИдентичностьОтклоняются() throws {
        XCTAssertThrowsError(try УчётВызовов(задача: "not-a-uuid"))
        try сФайлом(метаданные("22222222-2222-4222-8222-222222222222") + вызов()) {
            XCTAssertThrowsError(try прочитатьПрефикс($0, задача: задачаФикстуры))
        }
        try сФайлом(вызов()) { XCTAssertThrowsError(try прочитатьПрефикс($0, задача: задачаФикстуры)) }
    }
    func test_ХвостЖдётПереводСтрокиАПродолжениеДаётОдноСобытие() throws {
        let начало = try метаданные() + вызов()
        let хвост = try результат().dropLast()
        try сФайлом(начало + хвост) { путь in
            let первый = try прочитатьПрефикс(путь, задача: задачаФикстуры)
            XCTAssertEqual(первый.граница?.байт, начало.count)
            XCTAssertEqual(первый.хвостБайт, хвост.count)
            XCTAssertEqual(первый.события.count, 1)
            try (начало + хвост + Data([10])).write(to: путь)
            let второй = try прочитатьПрефикс(путь, задача: задачаФикстуры, после: первый.граница)
            XCTAssertEqual(второй.события.count, 1)
            XCTAssertEqual(второй.события.first?.направление, .результат)
            XCTAssertEqual(второй.граница?.строк, 3)
        }
    }
    func testИзменённыеАргументыТогоЖеКлючаКонфликтуют() throws {
        XCTAssertThrowsError(try сводка(метаданные() + вызов() + вызов(аргументы: "изменено")))
    }
    func testИзменениеНерелевантногоПрефиксаОтклоняется() throws {
        let начало = try метаданные() + строка("event_msg", ["type": "постороннее", "value": "A"])
        try сФайлом(начало) { путь in
            let первый = try прочитатьПрефикс(путь, задача: задачаФикстуры)
            let другое = try метаданные() + строка("event_msg", ["type": "постороннее", "value": "B"]) + вызов()
            try другое.write(to: путь)
            XCTAssertThrowsError(try прочитатьПрефикс(путь, задача: задачаФикстуры, после: первый.граница))
        }
    }
    func testНедостающиеПоляСохраняютНеизвестность() throws {
        let отчёт = try сводка(метаданные() + вызов(имя: NSNull()) +
            строка("response_item", ["type": "function_call"]) +
            строка("response_item", ["type": "function_call_output"]))
        XCTAssertEqual(отчёт.прямыхВызовов, 1)
        XCTAssertEqual(отчёт.вызовыБезИдентичности.count, 1)
        XCTAssertNil(отчёт.вызовы.first?.вызов.инструмент)
        XCTAssertEqual(отчёт.несопряжённыхРезультатов, 1)
    }
    func testСистемныеТекстыАргументыИВыводНеПопадаютВМодель() throws {
        let отчёт = try сводка(метаданные() +
            строка("response_item", ["type": "message", "role": "system", "content": "ПРИВАТНАЯ_СИСТЕМА"]) +
            строка("response_item", ["type": "reasoning", "content": "ПРИВАТНЫЕ_РАССУЖДЕНИЯ"]) +
            вызов() + результат())
        XCTAssertEqual(отчёт.прямыхВызовов, 1)
        let текст = String(decoding: try кодироватьСтатистику(отчёт), as: UTF8.self)
        XCTAssertFalse(текст.contains("ПРИВАТ"))
        XCTAssertEqual(отчёт.вызовы.first?.вызов.происхождение.строка, 4)
    }
    func test_НеверныйФорматИПовторКлючаНеПропускаются() throws {
        try сФайлом(метаданные() + Data("{broken}\n".utf8)) {
            XCTAssertThrowsError(try прочитатьПрефикс($0, задача: задачаФикстуры))
        }
        let дубль = Data("{\"type\":\"session_meta\",\"payload\":{\"id\":\"\(задачаФикстуры)\",\"id\":\"\(задачаФикстуры)\"}}\n".utf8)
        try сФайлом(дубль) { XCTAssertThrowsError(try прочитатьПрефикс($0, задача: задачаФикстуры)) }
    }
    func testОтрицательноеВремяИЧужоеСемействоНеПодтверждаютЗадержку() throws {
        let отчёт = try сводка(метаданные() + вызов() + результат(время: "2026-09-09T11:59:59Z") +
            вызов("call_b") + результат("call_b", произвольный: true))
        XCTAssertEqual(отчёт.вызовы.count, 2)
        XCTAssertTrue(отчёт.вызовы.allSatisfy { $0.задержкаНаносекунды == nil })
        XCTAssertEqual(отчёт.сопряжённыхРезультатов, 1)
        XCTAssertEqual(отчёт.несопряжённыхРезультатов, 1)
        XCTAssertEqual(отчёт.вызовы.last?.связь, .несовместимоеСемейство)
    }
}

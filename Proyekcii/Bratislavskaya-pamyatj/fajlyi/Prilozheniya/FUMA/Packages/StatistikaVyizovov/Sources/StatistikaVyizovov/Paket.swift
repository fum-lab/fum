import Foundation
import КонтейнерНаблюдений

struct ПакетСтатистики: Codable, Equatable, Sendable {
    let версия: Int
    let контракт: String
    let задача: String
    let порядок: Int
    let до: ГраницаПрефикса?
    let после: ГраницаПрефикса
    let события: [СобытиеВызова]
}
func описаниеПакета(_ пакет: ПакетСтатистики) -> ОписаниеНаблюдения {
    ОписаниеНаблюдения(идентификатор: пакет.задача + ":" + String(пакет.после.байт),
        тип: "статистика-вызовов/события-и-префикс", версияСхемы: 1,
        источник: пакет.задача, время: "граница-префикса:" + String(пакет.после.байт),
        спецификация: Data(контрактСтатистики.utf8))
}
func проверитьПакет(_ пакет: ПакетСтатистики, задача: String,
                   до: ГраницаПрефикса?, порядок: Int, учёт: УчётВызовов) throws -> УчётВызовов {
    guard пакет.версия == 1, пакет.контракт == контрактСтатистики, пакет.задача == задача,
          пакет.порядок == порядок, пакет.до == до else { throw ОшибкаСтатистики.повреждение }
    guard порядок > 0, порядок <= БюджетСтатистики.пакеты else { throw ОшибкаСтатистики.предел }
    try проверитьГраницу(пакет.после)
    if let до { try проверитьГраницу(до) }
    guard пакет.после.байт > (до?.байт ?? 0), пакет.после.строк > (до?.строк ?? 0) else {
        throw ОшибкаСтатистики.повреждение
    }
    var строка = до?.строк ?? 0
    var байт = до?.байт ?? 0
    func проверитьПромежуток(_ строки: Int, _ байты: Int) throws {
        guard строки >= 0, байты >= строки, байты <= строки * БюджетСтатистики.строка else {
            throw ОшибкаСтатистики.повреждение
        }
    }
    for событие in пакет.события {
        try проверитьСобытие(событие)
        let п = событие.происхождение
        guard п.строка > строка, п.строка <= пакет.после.строк,
              п.начало >= байт, п.конец <= пакет.после.байт else { throw ОшибкаСтатистики.повреждение }
        try проверитьПромежуток(п.строка - строка - 1, п.начало - байт)
        строка = п.строка; байт = п.конец
    }
    try проверитьПромежуток(пакет.после.строк - строка, пакет.после.байт - байт)
    var следующий = учёт
    try следующий.принять(пакет.события)
    return следующий
}
func декодироватьПакет(_ данные: Data) throws -> ПакетСтатистики {
    guard данные.count <= БюджетСтатистики.пакет else { throw ОшибкаСтатистики.предел }
    // Бюджет ключей конверта отделён от одной исходной JSONL-строки.
    var проверка = ПроверкаКлючей(байты: Array(данные), пределКлючей: 200_000)
    try проверка.значение()
    guard проверка.позиция == данные.count else { throw ОшибкаСтатистики.повреждение }
    do {
        let пакет = try JSONDecoder().decode(ПакетСтатистики.self, from: данные)
        guard try кодироватьСтатистику(пакет) == данные else { throw ОшибкаСтатистики.повреждение }
        return пакет
    } catch { throw ОшибкаСтатистики.повреждение }
}

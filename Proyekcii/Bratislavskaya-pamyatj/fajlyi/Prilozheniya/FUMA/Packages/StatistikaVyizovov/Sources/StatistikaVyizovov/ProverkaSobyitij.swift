import Foundation

func допустимыйХэш(_ значение: String) -> Bool {
    значение.utf8.count == 64 && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
}
func проверитьГраницу(_ значение: ГраницаПрефикса) throws {
    guard значение.байт > 0, значение.байт <= БюджетСтатистики.вход,
          значение.строк > 0, значение.строк <= БюджетСтатистики.строки,
          значение.строк <= значение.байт, допустимыйХэш(значение.sha256) else { throw ОшибкаСтатистики.повреждение }
}
func проверитьСобытие(_ событие: СобытиеВызова) throws {
    let п = событие.происхождение
    guard п.контракт == контрактСтатистики, п.строка > 1, п.строка <= БюджетСтатистики.строки,
          п.начало > 0, п.конец > п.начало, п.конец <= БюджетСтатистики.вход,
          п.конец - п.начало <= БюджетСтатистики.строка, допустимыйХэш(п.sha256),
          событие.идентификатор == nil || допустимыйТокен(событие.идентификатор) != nil,
          событие.инструмент == nil || допустимыйТокен(событие.инструмент) != nil,
          событие.направление != .результат || событие.инструмент == nil else { throw ОшибкаСтатистики.повреждение }
    if событие.момент.качество == .известно {
        guard let время = событие.момент.наносекундыОтЭпохи, время >= 0,
              время < 4_133_980_800_000_000_000 else { throw ОшибкаСтатистики.повреждение }
    } else if событие.момент.наносекундыОтЭпохи != nil { throw ОшибкаСтатистики.повреждение }
}

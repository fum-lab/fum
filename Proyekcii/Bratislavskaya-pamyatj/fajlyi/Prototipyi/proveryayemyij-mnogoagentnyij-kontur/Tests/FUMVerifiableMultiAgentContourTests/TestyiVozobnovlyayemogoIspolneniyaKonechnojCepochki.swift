import Foundation
import Testing

@testable import FUMVerifiableMultiAgentContour

@Suite("Возобновляемое исполнение конечной цепочки", .serialized)
struct ТестыВозобновляемогоИсполненияКонечнойЦепочки {
  @Test("Две зависимые карточки исполняются тремя сессиями в одном checkout")
  func двеКарточкиИсполняютсяТремяСессиями() throws {
    let отчёт =
      try ФикстурыВозобновляемогоИсполненияКонечнойЦепочки
      .выполнитьДвухшаговую(исполняемыйФайлПробника: путьПробника())

    #expect(отчёт.решение == "принято")
    #expect(отчёт.проверкаУниверсальногоИсполнителя == "допустимо")
    #expect(отчёт.проверкаДелегирования == "допустимо")
    #expect(отчёт.коммиты.count == 2)
    #expect(отчёт.исходнаяВершина != отчёт.готоваяВершина)
    #expect(отчёт.коммиты.last == отчёт.готоваяВершина)
    #expect(отчёт.задачиЦепочки.count == 3)
    #expect(Set(отчёт.задачиЦепочки).count == 3)
    #expect(отчёт.процессыСессий.count == 3)
    #expect(Set(отчёт.процессыСессий).count == 3)
    #expect(отчёт.состоянияСелектора == ["ready", "ready", "not_ready"])
    #expect(отчёт.числоСозданийНачальнойЗадачи == 1)
    #expect(отчёт.числоСозданийПродолжений == 2)
    #expect(отчёт.числоСвязанныхКвитанций == 2)
    #expect(отчёт.финальноеЧистоеЗавершение)
    #expect(отчёт.финальныйПовторИдемпотентен)
    #expect(!отчёт.идентификаторРабочейКопии.isEmpty)
    #expect(отчёт.рабочаяСсылка == "refs/heads/роль/писатель")
    #expect(отчёт.целеваяСсылка == "refs/heads/master")
    #expect(отчёт.целеваяВершинаДо == отчёт.целеваяВершинаПосле)
    #expect(отчёт.однаФизическаяРабочаяКопия)
    #expect(отчёт.диапазонОднородительский)
    #expect(отчёт.временныеСсылкиОтсутствуют)
  }

  @Test("Готовый пакет закрепляет полный диапазон, diff и только будущий PR-маршрут")
  func пакетПередачиЗакрепляетФактическийДиапазон() throws {
    let отчёт =
      try ФикстурыВозобновляемогоИсполненияКонечнойЦепочки
      .выполнитьДвухшаговую(исполняемыйФайлПробника: путьПробника())

    #expect(отчёт.пакетПередачиПроверен)
    #expect(отчёт.подменаПакетаОтклонена)
    #expect(отчёт.самосогласованнаяПодменаКорнейОтклонена)
    #expect(отчёт.коммиты == отчёт.коммитыПакета)
    #expect(!отчёт.путиСовокупногоИзменения.isEmpty)
    #expect(отчёт.хэшСовокупногоИзменения.hasPrefix("sha256:"))
    #expect(отчёт.внешниеЗадачи.count == 2)
    #expect(Set(отчёт.внешниеЗадачи).isDisjoint(with: отчёт.задачиЦепочки))
    #expect(!отчёт.созданЗапросНаСлияние)
    #expect(!отчёт.результатПринят)
  }

  @Test("Сбои после продолжения восстанавливаются, а подмена дерева отклоняется")
  func границыСбоевНеУдваиваютПереход() throws {
    let отчёт =
      try ФикстурыВозобновляемогоИсполненияКонечнойЦепочки
      .проверитьГраницыСбоев(исполняемыйФайлПробника: путьПробника())

    #expect(отчёт.неоднозначностьЗаблокировалаКоммит)
    #expect(отчёт.неоднозначностьНеПовторилаСоздание)
    #expect(отчёт.вершинаПриНеоднозначностиНеИзменилась)
    #expect(отчёт.потерянныйОтветВосстановленПоКвитанции)
    #expect(отчёт.потерянныйОтветНеПовторилСоздание)
    #expect(отчёт.точныйПовторНеСоздалВторойКоммит)
    #expect(отчёт.изменённыйПовторОтклонён)
    #expect(отчёт.остановкаПослеПодтвержденияВосстановлена)
    #expect(отчёт.остановкаНеПовторилаСоздание)
    #expect(отчёт.вершинаПриОстановкеНеИзменилась)
    #expect(отчёт.подменённоеДеревоОтклонено)
    #expect(отчёт.подменаДереваНеПродвинулаВетку)
    #expect(отчёт.подменаДереваНеПовторилаСоздание)
    #expect(отчёт.подменаДереваПослеИсправленияВосстановлена)
    #expect(отчёт.превышениеТокеновОтклонено)
    #expect(отчёт.превышениеСекундОтклонено)
    #expect(отчёт.превышениеИзменённыхФайловОтклонено)
    #expect(отчёт.незаявленныйПутьОтклонён)
    #expect(отчёт.заявленныйПутьВнеОбластиОтклонён)
    #expect(отчёт.неуспешнаяПроверкаОтклонена)
  }

  private func путьПробника() throws -> URL {
    let адрес = Bundle(for: МеткаНабораВозобновляемойЦепочки.self).bundleURL
      .deletingLastPathComponent()
      .appending(path: "FUMWorkPackageProbe", directoryHint: .notDirectory)
    guard FileManager.default.isExecutableFile(atPath: адрес.path) else {
      throw ОшибкаТестаВозобновляемойЦепочки.пробникНеНайден(адрес.path)
    }
    return адрес
  }
}

private final class МеткаНабораВозобновляемойЦепочки: NSObject {}

private enum ОшибкаТестаВозобновляемойЦепочки: Error {
  case пробникНеНайден(String)
}

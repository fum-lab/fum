  @Test("Ограждённый редуктор принимает только связанное разрешением событие и пару сборки")
  func ограждённыйРедукторСвязываетРешениеИВершины() throws {
    let дочернийСнимок = снимок(
      ожидаемаяВершинаСборки: объект("a"),
      ожидаемаяВершинаРебёнкаВСборке: объект("a")
    )
    let дочернееРазрешение = try #require(
      ПроверкаКорневогоРевьюИИнтеграцииЦепочки.проверить(дочернийСнимок).разрешение)
    let подготовлено = СостояниеКорневойИнтеграцииЦепочки(
      разрешение: дочернееРазрешение)

    let неверныйХэш = РедукторКорневойИнтеграцииЦепочки.применить(
      .сравнитьИЗаменитьЦель(
        хэшРешения: хэш("9"),
        целеваяСсылка: дочернееРазрешение.целеваяСсылка,
        ожидаемаяВершина: объект("a"),
        наблюдаемаяВершина: объект("a"),
        новаяВершина: объект("c")
      ),
      к: подготовлено
    )
    #expect(неверныйХэш.кодОтказа == "ограждение_решения_не_совпадает")
    #expect(неверныйХэш.состояниеПерехода == .подготовлено)

    let невернаяСсылка = РедукторКорневойИнтеграцииЦепочки.применить(
      .сравнитьИЗаменитьЦель(
        хэшРешения: дочернееРазрешение.хэшРешения,
        целеваяСсылка: "refs/heads/другая",
        ожидаемаяВершина: объект("a"),
        наблюдаемаяВершина: объект("a"),
        новаяВершина: объект("c")
      ),
      к: подготовлено
    )
    #expect(невернаяСсылка.кодОтказа == "ограждение_ссылки_не_совпадает")

    let невернаяВершина = РедукторКорневойИнтеграцииЦепочки.применить(
      .сравнитьИЗаменитьЦель(
        хэшРешения: дочернееРазрешение.хэшРешения,
        целеваяСсылка: дочернееРазрешение.целеваяСсылка,
        ожидаемаяВершина: объект("9"),
        наблюдаемаяВершина: объект("a"),
        новаяВершина: объект("c")
      ),
      к: подготовлено
    )
    #expect(невернаяВершина.кодОтказа == "ограждение_вершин_не_совпадает")

    let принято = РедукторКорневойИнтеграцииЦепочки.применить(
      .сравнитьИЗаменитьЦель(
        хэшРешения: дочернееРазрешение.хэшРешения,
        целеваяСсылка: дочернееРазрешение.целеваяСсылка,
        ожидаемаяВершина: объект("a"),
        наблюдаемаяВершина: объект("a"),
        новаяВершина: объект("c")
      ),
      к: подготовлено
    )
    let невернаяПара = РедукторКорневойИнтеграцииЦепочки.применить(
      .обновитьСсылкуРебёнкаВСборке(
        хэшРешения: дочернееРазрешение.хэшРешения,
        ожидаемаяВершинаСборки: объект("a"),
        наблюдаемаяВершинаСборки: объект("a"),
        ожидаемаяВершинаРебёнка: объект("9"),
        наблюдаемаяВершинаРебёнка: объект("a"),
        новаяВершинаРебёнка: объект("c")
      ),
      к: принято

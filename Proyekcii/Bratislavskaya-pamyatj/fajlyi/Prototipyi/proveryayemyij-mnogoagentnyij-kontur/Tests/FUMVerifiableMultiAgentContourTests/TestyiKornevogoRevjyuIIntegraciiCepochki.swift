  @Test("Только принятие и точное сравнение разрешают движение цели")
  func сравнениеИЗаменаЗакрытыОтНеопределённости() throws {
    for исход in [
      ИсходКорневогоРевьюЦепочки.наДоработку,
      .отклонено,
      .неопределённо,
    ] {
      #expect(
        ПроверкаКорневогоРевьюИИнтеграцииЦепочки.проверить(снимок(исход: исход))
          .разрешение == nil)
    }

    let допустимаяДоработка = ПроверкаКорневогоРевьюИИнтеграцииЦепочки.проверить(
      снимок(исход: .наДоработку, новоеПоколениеДоработки: "назначение.2"))
    #expect(допустимаяДоработка.кодыНарушений.isEmpty)
    #expect(допустимаяДоработка.разрешение == nil)
    #expect(допустимаяДоработка.поколениеДоработки == "назначение.2")
    #expect(
      ПроверкаКорневогоРевьюИИнтеграцииЦепочки.проверить(
        снимок(исход: .наДоработку, новоеПоколениеДоработки: "назначение.1")
      ).кодыНарушений.contains("доработка_не_создала_новое_поколение"))

    let подготовлено = try состояниеИнтеграции(из: снимок())
    let неизвестныйКонфликт = РедукторКорневойИнтеграцииЦепочки.применить(
      .обнаружитьНеизвестныйКонфликт,
      к: подготовлено
    )
    #expect(неизвестныйКонфликт.состояниеПерехода == .неизвестныйКонфликт)
    #expect(неизвестныйКонфликт.текущаяВершинаЦели == объект("a"))
    #expect(неизвестныйКонфликт.принятаяВершина == объект("c"))

    let проиграно = РедукторКорневойИнтеграцииЦепочки.применить(
      .зафиксироватьПроигрышСравненияИЗамены(наблюдаемаяВершина: объект("9")),
      к: подготовлено
    )
    #expect(проиграно.состояниеПерехода == .сравнениеПроиграно)
    #expect(проиграно.текущаяВершинаЦели == объект("9"))
    #expect(проиграно.принятаяВершина == объект("c"))
  }


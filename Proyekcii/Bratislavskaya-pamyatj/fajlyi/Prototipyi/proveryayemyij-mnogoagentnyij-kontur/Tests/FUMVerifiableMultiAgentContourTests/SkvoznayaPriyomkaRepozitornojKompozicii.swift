import Foundation
import Testing

@testable import FUMVerifiableMultiAgentContour

@Suite("Автономная сквозная приёмка репозиторной композиции")
struct ТестыСквознойПриёмкиРепозиторнойКомпозиции {
  @Test("единый локальный стенд доказывает исполнение, интеграцию, восстановление и CAS")
  func единыйСтендЗакрываетКритерииКарточки() throws {
    let отчёт = try СквознаяПриёмкаРепозиторнойКомпозиции.выполнить()

    #expect(отчёт.решение == .принято)
    #expect(отчёт.проверки.allSatisfy { $0.пройдена })
    #expect(
      Set(отчёт.проверки.map(\.идентификатор))
        == Set([
          "два-параллельных-кандидата",
          "бесконфликтная-и-разрешённая-интеграция",
          "неизвестный-конфликт-сохранён",
          "покрытие-пишущих-запусков",
          "fork-и-проект-передали-результаты-в-общего-родителя",
          "свежие-клоны-восстановили-снимки-и-управление",
          "повтор-воспроизводит-паспорта-и-деревья",
          "прерывания-перед-cas-атомарны",
          "пробник-автономен-и-не-подменяет-инфраструктуру",
        ]))

    #expect(отчёт.покрытие.допущеноПишущихЗапусков == 5)
    #expect(отчёт.покрытие.кандидатныхКоммитов == 2)
    #expect(отчёт.покрытие.бездействий == 1)
    #expect(отчёт.покрытие.блокировокДоЗаписи == 1)
    #expect(отчёт.покрытие.публикационныхОтказов == 1)
    #expect(отчёт.покрытие.конфликтовИнтеграции == 1)
    #expect(отчёт.покрытие.искусственныхПустыхКоммитов == 0)
    #expect(отчёт.покрытие.покрытыхКоммитов == 2)
    #expect(отчёт.покрытие.требующихКоммита == 2)

    #expect(отчёт.событияПишущихЗапусков.count == 5)
    #expect(Set(отчёт.событияПишущихЗапусков.map(\.идентификаторЗапуска)).count == 5)
    #expect(отчёт.событияПишущихЗапусков.allSatisfy { $0.допущен })
    #expect(
      Set(отчёт.событияПишущихЗапусков.map(\.идентификаторЗапуска))
        == Set(["run-a", "run-b", "run-no-op", "run-blocked", "run-publication-rejected"])
    )
    #expect(отчёт.событияПишущихЗапусков.filter(\.требовалсяКоммит).count == 2)
    #expect(
      отчёт.событияПишущихЗапусков.filter { $0.созданныйКоммит != nil }.allSatisfy {
        $0.базовоеДерево != $0.итоговоеДерево
      }
    )
    #expect(
      отчёт.событияПишущихЗапусков.filter { $0.созданныйКоммит == nil }.allSatisfy {
        $0.итоговоеДерево == nil && $0.отпечатокПаспорта == nil
      }
    )

    #expect(отчёт.событияИнтеграции.count == 3)
    #expect(
      Set(отчёт.событияИнтеграции.map(\.идентификаторПопытки))
        == Set(["integrate-a", "integrate-b-resolved", "unknown-conflict"])
    )
    #expect(
      отчёт.событияИнтеграции.filter { $0.исход == .resolutionRequired }.allSatisfy {
        $0.целевойКоммитДо == $0.целевойКоммитПосле && $0.отпечатокДиагностики != nil
      }
    )

    #expect(отчёт.первыйОтпечатокПаспорта == отчёт.повторныйОтпечатокПаспорта)
    #expect(отчёт.первыеОтпечаткиПаспортов == отчёт.повторныеОтпечаткиПаспортов)
    #expect(отчёт.версияПрофиляЭквивалентностиПаспортов == 1)
    #expect(
      отчёт.исключённыеПоляЭквивалентностиПаспортов
        == [
          "candidate.execution_request_sha256",
          "candidate.source_repository_sha256",
          "integration.candidates[].passport_sha256",
          "integration.request_sha256",
        ])
    #expect(
      Set(отчёт.первыеОтпечаткиПаспортов.keys)
        == Set([
          "candidate:a",
          "candidate:b",
          "integration:a",
          "integration:b",
          "diagnostic:unknown-conflict",
          "composition",
        ]))
    #expect(отчёт.первыеИтоговыеДеревья == отчёт.повторныеИтоговыеДеревья)
    #expect(!отчёт.первыеИтоговыеДеревья.isEmpty)
    #expect(
      Set(отчёт.точкиПрерыванийПередСравнениемИЗаменой)
        == Set([
          "candidate-a",
          "candidate-b",
          "integration-a",
          "integration-b",
          "fork",
          "core",
          "project",
          "parent",
        ]))
    #expect(отчёт.точкиПрерыванийПередСравнениемИЗаменой.count == 8)
    #expect(отчёт.первыеВосстановленныеОчереди == отчёт.повторныеВосстановленныеОчереди)
    #expect(Set(отчёт.первыеВосстановленныеОчереди.keys) == Set(["fork", "project"]))
    #expect(
      отчёт.первыеВосстановленныеОчереди.values.allSatisfy {
        $0.каноническоеСостояние
          && $0.служебныеСсылкиНеОпубликованы
          && $0.последовательностьВосстановленногоБилета
            == $0.последовательностьЗавершённогоБилета + 1
      }
    )
    #expect(
      отчёт.границаДоказательства
        == "Локальная автономная фикстура без сети, секретов и модельных вызовов; внешняя инфраструктура и независимость моделей не заявлены."
    )
  }
}

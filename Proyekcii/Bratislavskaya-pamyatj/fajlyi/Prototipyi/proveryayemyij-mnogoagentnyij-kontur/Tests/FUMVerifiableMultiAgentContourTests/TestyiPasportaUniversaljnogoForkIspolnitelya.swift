  private func проверитьФикстуру(
    _ имя: String
  ) throws -> ОтчётПроверкиУниверсальногоФоркИсполнителя {
    try ФикстурыУниверсальногоФоркИсполнителя.сФикстурой(имя: имя) { фикстура in
      ПроверкаУниверсальногоФоркИсполнителя.проверить(
        фикстура.регистрация,
        контекст: фикстура.контекст
      )
    }
  }

  private func изменить(
    _ исходный: [String: Any],
    раздел: String?,
    ключ: String,
    значение: Any
  ) -> [String: Any] {
    var результат = исходный
    guard let раздел else {
      результат[ключ] = значение
      return результат
    }
    var вложенный = результат[раздел] as? [String: Any] ?? [:]
    вложенный[ключ] = значение
    результат[раздел] = вложенный
    return результат
  }

  private func строкиИдентичностиСхемы(_ значение: Any) -> [(String, String)] {
    if let объект = значение as? [String: Any] {
      var результат: [(String, String)] = []
      for (ключ, вложенное) in объект {
        if ключ == "$id" || ключ == "$ref", let строка = вложенное as? String {
          результат.append((ключ, строка))
        }
        результат += строкиИдентичностиСхемы(вложенное)
      }
      return результат
    }
    if let массив = значение as? [Any] {
      return массив.flatMap(строкиИдентичностиСхемы)
    }
    return []
  }

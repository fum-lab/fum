  @Test("Дочерняя рабочая ветка имеет собственный готовый шаг прямого селектора")
  func дочернийСелекторГотовДляРабочейВетки() throws {
    try ФикстурыУниверсальногоФоркИсполнителя.сФикстурой(имя: "валидная") { фикстура in
      let корень = фикстура.контекст.пишущийКлонИсполнителя
      let путьСелектора = корень.appendingPathComponent(
        "Инструменты/fum-sleduyusjhij-shag-vetki/scripts/branch-next-step.py"
      )
      let процесс = Process()
      let путиПоиска =
        ProcessInfo.processInfo.environment["PATH"]?
        .split(separator: ":") ?? []
      let исполняемыйФайлИнтерпретатора = путиПоиска.lazy
        .map { URL(fileURLWithPath: String($0)).appendingPathComponent("python3") }
        .first { FileManager.default.isExecutableFile(atPath: $0.path) }
      guard let исполняемыйФайлИнтерпретатора else {
        Issue.record("Не найден обязательный python3 в PATH адресной фикстуры.")
        return
      }
      процесс.executableURL = исполняемыйФайлИнтерпретатора
      процесс.arguments = [
        путьСелектора.path, "show", "--repo-root", корень.path, "--json",
      ]
      процесс.currentDirectoryURL = корень
      процесс.environment = ProcessInfo.processInfo.environment.filter { ключ, _ in
        !ключ.hasPrefix("GIT_")
      }
      let вывод = Pipe()
      let ошибки = Pipe()
      процесс.standardOutput = вывод
      процесс.standardError = ошибки
      try процесс.run()
      процесс.waitUntilExit()
      let данныеВывода = вывод.fileHandleForReading.readDataToEndOfFile()
      let данныеОшибок = ошибки.fileHandleForReading.readDataToEndOfFile()
      let текстОшибок = String(data: данныеОшибок, encoding: .utf8) ?? "<не-UTF-8>"
      #expect(процесс.terminationStatus == 0, "Ошибка селектора: \(текстОшибок)")
      let ответ = try #require(
        JSONSerialization.jsonObject(with: данныеВывода) as? [String: Any]
      )
      #expect(ответ["state"] as? String == "ready")
      #expect(ответ["branch_ref"] as? String == "refs/heads/роль/писатель")
      #expect(
        ответ["record_path"] as? String
          == "Планирование/следующие-шаги-веток/исполнитель.md"
      )
      let путьКарточки =
        "Планирование/карточки-шагов/🟡-FUM-STEP-9001-локальная-карточка-исполнителя.md"
      #expect(ответ["card_path"] as? String == путьКарточки)
      let данныеКарточки = try Data(contentsOf: корень.appendingPathComponent(путьКарточки))
      let точныйХэш =
        "sha256:"
        + SHA256.hash(data: данныеКарточки).map {
          String(format: "%02x", $0)
        }.joined()
      #expect(ответ["card_content_sha256"] as? String == точныйХэш)
    }
  }


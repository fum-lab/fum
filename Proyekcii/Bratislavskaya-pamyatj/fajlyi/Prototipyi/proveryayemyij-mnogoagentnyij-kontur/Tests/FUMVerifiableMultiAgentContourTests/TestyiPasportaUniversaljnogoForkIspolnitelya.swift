  @Test("Новая схема закрыта и не превращает историческую специализацию в целевой вид")
  func новаяСхемаЗакрытаИОтделенаОтИсторической() throws {
    let регистрация = try СхемыУниверсальногоФоркИсполнителя.загрузитьРегистрацию()
    let паспорт = try СхемыУниверсальногоФоркИсполнителя.загрузитьПаспортРебёнка()
    let историческая = try RepositoryCompositionSchema.load()

    let текстРегистрации = try #require(String(data: регистрация, encoding: .utf8))
    let текстПаспорта = try #require(String(data: паспорт, encoding: .utf8))
    let историческийТекст = try #require(String(data: историческая, encoding: .utf8))

    #expect(текстРегистрации.contains("\"поколение_схемы\""))
    #expect(текстРегистрации.contains("\"универсальный_исполнитель\""))
    #expect(текстПаспорта.contains("\"универсальный_профиль\""))
    #expect(текстРегистрации.contains("\"additionalProperties\": false"))
    #expect(текстПаспорта.contains("\"additionalProperties\": false"))
    #expect(!текстРегистрации.contains("specialized_subnode"))
    #expect(!текстПаспорта.contains("specialized_subnode"))
    #expect(историческийТекст.contains("specialized_subnode"))

    for данныеСхемы in [регистрация, паспорт] {
      let объектСхемы = try #require(
        JSONSerialization.jsonObject(with: данныеСхемы) as? [String: Any]
      )
      let определения = try #require(объектСхемы["$defs"] as? [String: Any])
      for (ключ, значение) in строкиИдентичностиСхемы(объектСхемы) {
        #expect(значение.unicodeScalars.allSatisfy { $0.value <= 0x7f })
        if ключ == "$id" {
          let адрес = try #require(URL(string: значение))
          #expect(адрес.scheme?.isEmpty == false)
        } else if значение.hasPrefix("#") {
          let начало = "#/$defs/"
          #expect(значение.hasPrefix(начало))
          let кодированныйКлюч = String(значение.dropFirst(начало.count))
          let декодированныйКлюч = try #require(
            кодированныйКлюч.removingPercentEncoding
          )
          let косаяЧерта = String(UnicodeScalar(47)!)
          let тильда = String(UnicodeScalar(126)!)
          let ключОпределения =
            декодированныйКлюч
            .replacingOccurrences(of: тильда + "1", with: косаяЧерта)
            .replacingOccurrences(of: тильда + "0", with: тильда)
          #expect(определения[ключОпределения] != nil)
        }
      }
    }
  }


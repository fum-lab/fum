  }

  private static func каноническийПутьРепозитория(
    _ значение: String,
    относительно репозиторий: URL
  ) -> String {
    if let адрес = URL(string: значение), адрес.isFileURL {
      return каноническийПуть(адрес)
    }
    if значение.hasPrefix("/") {
      return каноническийПуть(URL(fileURLWithPath: значение, isDirectory: true))
    }
    let адрес = репозиторий.appendingPathComponent(значение, isDirectory: true)
    return каноническийПуть(адрес)
  }

  private static func каноническийПуть(_ адрес: URL) -> String {
    адрес.standardizedFileURL.resolvingSymlinksInPath().path
  }

  private static func относительныйПуть(_ адрес: URL, внутри основа: URL) -> String? {
    let компонентыАдреса = URL(
      fileURLWithPath: каноническийПуть(адрес),
      isDirectory: true
    ).pathComponents
    let компонентыОсновы = URL(
      fileURLWithPath: каноническийПуть(основа),
      isDirectory: true
    ).pathComponents
    guard компонентыАдреса.count > компонентыОсновы.count,
      Array(компонентыАдреса.prefix(компонентыОсновы.count)) == компонентыОсновы
    else {
      return nil
    }
    return компонентыАдреса.dropFirst(компонентыОсновы.count).joined(separator: "/")
  }


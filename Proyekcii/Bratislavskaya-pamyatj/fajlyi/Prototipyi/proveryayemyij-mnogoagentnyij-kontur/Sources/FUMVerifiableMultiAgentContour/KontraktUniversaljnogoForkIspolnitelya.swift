  private static func строчнаяШестнадцатеричнаяСтрока(_ значение: String) -> Bool {
    !значение.isEmpty
      && значение.utf8.allSatisfy {
        ($0 >= 48 && $0 <= 57) || ($0 >= 97 && $0 <= 102)
      }
  }

  private static func полнаяСсылкаВетки(_ значение: String) -> Bool {
    let начало = "refs/heads/"
    guard значение.hasPrefix(начало), значение.count > начало.count else {
      return false
    }
    let остаток = String(значение.dropFirst(начало.count))
    let запрещённыеСкалярныеЗначения: Set<UInt32> = [
      32, 126, 94, 58, 63, 42, 91, 92,
    ]
    let содержитЗапрещённыйСимвол = остаток.unicodeScalars.contains {
      $0.value < 32 || $0.value == 127 || запрещённыеСкалярныеЗначения.contains($0.value)
    }
    let компоненты = остаток.split(separator: "/", omittingEmptySubsequences: false)
    return !содержитЗапрещённыйСимвол
      && !остаток.contains("..")
      && !остаток.contains("@{")
      && остаток != "@"
      && !компоненты.contains(where: {
        $0.isEmpty || $0.hasPrefix(".") || $0.hasSuffix(".") || $0.hasSuffix(".lock")
      })
  }

  private static func хэш(_ данные: Data) -> String {
    "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
  }

  private static func путьДиагностики(_ остаток: String) -> String {

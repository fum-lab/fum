        добавить(
          код: "повторный_ключ",
          путь: путь,
          сообщение: "JSON-объект содержит повторный ключ.",
          в: &нарушения
        )
      }
    } catch {
      добавить(
        код: "неверная_структура",
        путь: "",
        сообщение: "Регистрация не является завершённым JSON-объектом.",
        в: &нарушения
      )
    }

    guard let корень = (try? JSONSerialization.jsonObject(with: данные)) as? [String: Any]
    else {
      добавить(
        код: "неверная_структура",
        путь: "",
        сообщение: "Верхний уровень регистрации должен быть JSON-объектом.",
        в: &нарушения
      )
      return отчёт(нарушения: нарушения)
    }
    проверитьЗакрытыйОбъект(
      корень,
      ключи: корневыеКлючиРегистрации,
      путь: "",
      нарушения: &нарушения
    )
    guard let сырьёЯдра = корень["ядро"] as? [String: Any],
      let сырьёСборки = корень["сборка"] as? [String: Any],
      let сырьёИсполнителя = корень["исполнитель"] as? [String: Any]
    else {
      добавить(
        код: "неверный_тип",
        путь: "",
        сообщение: "Ядро, сборка и исполнитель должны быть объектами.",
        в: &нарушения
      )
      return отчёт(нарушения: нарушения)
    }
    проверитьЗакрытыйОбъект(
      сырьёЯдра, ключи: ключиЯдра, путь: путьДиагностики("ядро"), нарушения: &нарушения)
    проверитьЗакрытыйОбъект(
      сырьёСборки, ключи: ключиСборки, путь: путьДиагностики("сборка"), нарушения: &нарушения)
    проверитьЗакрытыйОбъект(
      сырьёИсполнителя,
      ключи: ключиИсполнителя,
      путь: путьДиагностики("исполнитель"),
      нарушения: &нарушения
    )

    guard
      let регистрация = try? JSONDecoder().decode(
        РегистрацияУниверсальногоФоркИсполнителя.self,
        from: данные
      )
    else {
      добавить(
        код: "неверный_тип",
        путь: "",
        сообщение: "Регистрация не соответствует типизированному контракту v2.",
        в: &нарушения
      )
      return отчёт(
        нарушения: нарушения,
        идентификаторРебёнка: сырьёИсполнителя["идентификатор_ребёнка"] as? String,
        идентификаторРепозитория: сырьёИсполнителя["идентификатор_репозитория"] as? String,
        идентификаторПрофиля: сырьёИсполнителя["идентификатор_профиля"] as? String,
        хэшПолномочий: сырьёИсполнителя["хэш_полномочий"] as? String,
        поколениеНазначения: сырьёИсполнителя["поколение_назначения"] as? String
      )
    }

    проверитьСемантикуРегистрации(регистрация, нарушения: &нарушения)
    guard нарушения.isEmpty else {
      return отчёт(
        нарушения: нарушения,
        регистрация: регистрация
      )
    }

    return проверитьГит(
      регистрация,
      контекст: контекст,
      начальныеНарушения: нарушения
    )
  }

  private static func проверитьСемантикуРегистрации(
    _ регистрация: РегистрацияУниверсальногоФоркИсполнителя,
    нарушения: inout [НарушениеПроверкиУниверсальногоФоркИсполнителя]
  ) {
    if регистрация.поколениеСхемы != 2 {
      добавить(
        код: "неподдерживаемое_поколение_схемы",
        путь: путьДиагностики("поколение_схемы"),
        сообщение: "Поддерживается только самостоятельный контракт v2.",
        в: &нарушения
      )
    }
    if регистрация.исполнитель.вид != "универсальный_исполнитель" {
      добавить(
        код: "неверный_вид_исполнителя",
        путь: путьДиагностики("исполнитель/вид"),
        сообщение: "Регистрация должна объявлять универсального исполнителя.",
        в: &нарушения
      )
    }
    let идентификаторы: [(String, String)] = [
      (регистрация.идентификаторРегистрации, путьДиагностики("идентификатор_регистрации")),
      (регистрация.идентификаторКомпозиции, путьДиагностики("идентификатор_композиции")),
      (
        регистрация.ядро.идентификаторРепозитория, путьДиагностики("ядро/идентификатор_репозитория")
      ),
      (
        регистрация.сборка.идентификаторРепозитория,
        путьДиагностики("сборка/идентификатор_репозитория")
      ),
      (
        регистрация.исполнитель.идентификаторРебёнка,
        путьДиагностики("исполнитель/идентификатор_ребёнка")
      ),
      (
        регистрация.исполнитель.идентификаторРепозитория,
        путьДиагностики("исполнитель/идентификатор_репозитория")
      ),
      (
        регистрация.исполнитель.идентификаторВышестоящегоРепозитория,
        путьДиагностики("исполнитель/идентификатор_вышестоящего_репозитория")
      ),
      (
        регистрация.исполнитель.идентификаторКомпозиции,
        путьДиагностики("исполнитель/идентификатор_композиции")
      ),
      (
        регистрация.исполнитель.идентификаторПрофиля,
        путьДиагностики("исполнитель/идентификатор_профиля")
      ),
      (
        регистрация.исполнитель.поколениеНазначения,
        путьДиагностики("исполнитель/поколение_назначения")
      ),
    ]
    for (значение, путь) in идентификаторы {
      проверитьИдентификатор(значение, путь: путь, нарушения: &нарушения)
    }
    проверитьАдресРепозитория(
      регистрация.ядро.адресРепозитория,
      путь: путьДиагностики("ядро/адрес_репозитория"),
      нарушения: &нарушения
    )
    проверитьАдресРепозитория(
      регистрация.сборка.адресРепозитория,
      путь: путьДиагностики("сборка/адрес_репозитория"),
      нарушения: &нарушения
    )
    проверитьАдресРепозитория(
      регистрация.исполнитель.адресРепозитория,
      путь: путьДиагностики("исполнитель/адрес_репозитория"),
      нарушения: &нарушения
    )
    проверитьОбъектГит(
      регистрация.ядро.опубликованноеПоколение,
      путь: путьДиагностики("ядро/опубликованное_поколение"),
      нарушения: &нарушения
    )
    проверитьОбъектГит(
      регистрация.исполнитель.идентификаторСнимка,
      путь: путьДиагностики("исполнитель/идентификатор_снимка"),
      нарушения: &нарушения
    )
    проверитьХэшШа256(
      регистрация.исполнитель.хэшПолномочий,
      путь: путьДиагностики("исполнитель/хэш_полномочий"),
      нарушения: &нарушения
    )
    проверитьХэшШа256(
      регистрация.исполнитель.хэшПаспортаРебёнка,
      путь: путьДиагностики("исполнитель/хэш_паспорта_ребёнка"),
      нарушения: &нарушения
    )
    if регистрация.исполнитель.идентификаторВышестоящегоРепозитория
      != регистрация.ядро.идентификаторРепозитория
    {
      добавить(
        код: "неверный_репозиторий_ядра",
        путь: путьДиагностики("исполнитель/идентификатор_вышестоящего_репозитория"),
        сообщение: "Исполнитель должен ссылаться на зарегистрированное ядро.",
        в: &нарушения
      )
    }
    if регистрация.исполнитель.идентификаторКомпозиции
      != регистрация.идентификаторКомпозиции
    {
      добавить(
        код: "идентификатор_композиции_не_совпадает",
        путь: путьДиагностики("исполнитель/идентификатор_композиции"),
        сообщение: "Исполнитель должен принадлежать корневой зарегистрированной композиции.",
        в: &нарушения
      )
    }
    if !полнаяСсылкаВетки(регистрация.ядро.зеркальнаяСсылка)
      || !полнаяСсылкаВетки(регистрация.сборка.живаяСсылка)
      || !полнаяСсылкаВетки(регистрация.исполнитель.рабочаяСсылка)
    {
      добавить(
        код: "неверная_ссылка_ветки",
        путь: "",
        сообщение: "Все веточные ссылки должны быть полными refs/heads/... ссылками.",
        в: &нарушения
      )
    }
    проверитьОтносительныйПуть(
      регистрация.исполнитель.путьПодмодуля,
      путь: путьДиагностики("исполнитель/путь_подмодуля"),
      нарушения: &нарушения
    )
    проверитьОтносительныйПуть(
      регистрация.исполнитель.путьПаспортаРебёнка,
      путь: путьДиагностики("исполнитель/путь_паспорта_ребёнка"),
      нарушения: &нарушения
    )
    let идентификаторыРепозиториев = [
      регистрация.ядро.идентификаторРепозитория,
      регистрация.сборка.идентификаторРепозитория,
      регистрация.исполнитель.идентификаторРепозитория,
    ]
    if Set(идентификаторыРепозиториев).count != идентификаторыРепозиториев.count {
      добавить(
        код: "совпадающие_идентификаторы_репозиториев",
        путь: "",
        сообщение: "Ядро, fork-исполнитель и сборка должны иметь разные идентификаторы.",
        в: &нарушения
      )
    }
  }

  private static func проверитьГит(
    _ регистрация: РегистрацияУниверсальногоФоркИсполнителя,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя,
    начальныеНарушения: [НарушениеПроверкиУниверсальногоФоркИсполнителя]
  ) -> ОтчётПроверкиУниверсальногоФоркИсполнителя {
    var нарушения = начальныеНарушения
    let исполнитель = регистрация.исполнитель
    guard
      let репозиторийЯдра = контекст.репозиторииПоИдентификатору[
        регистрация.ядро.идентификаторРепозитория
      ],
      let репозиторийИсполнителя = контекст.репозиторииПоИдентификатору[
        исполнитель.идентификаторРепозитория
      ],
      let репозиторийСборки = контекст.репозиторииПоИдентификатору[
        регистрация.сборка.идентификаторРепозитория
      ]
    else {
      добавить(
        код: "репозиторий_не_найден",
        путь: "",
        сообщение: "Контекст не сопоставляет все устойчивые идентификаторы с репозиториями.",
        в: &нарушения
      )
      return отчёт(нарушения: нарушения, регистрация: регистрация)
    }

    проверитьСвязьАдресовРегистрации(
      регистрация,
      контекст: контекст,
      нарушения: &нарушения
    )
    проверитьОбъектГит(
      контекст.идентификаторСнимкаСборки,
      путь: путьДиагностики("контекст/идентификатор_снимка_сборки"),
      нарушения: &нарушения
    )
    let локальныеРепозитории = [
      каноническийПуть(репозиторийЯдра),
      каноническийПуть(репозиторийИсполнителя),
      каноническийПуть(репозиторийСборки),
    ]
    if Set(локальныеРепозитории).count != локальныеРепозитории.count {
      добавить(
        код: "совпадающие_локальные_репозитории",
        путь: путьДиагностики("контекст/репозитории"),
        сообщение: "Ядро, fork-исполнитель и сборка должны быть разными bare-репозиториями.",
        в: &нарушения
      )
    }
    guard нарушения.isEmpty else {
      return отчёт(нарушения: нарушения, регистрация: регистрация)
    }

    do {
      for (идентификатор, репозиторий) in [
        (регистрация.ядро.идентификаторРепозитория, репозиторийЯдра),
        (исполнитель.идентификаторРепозитория, репозиторийИсполнителя),
        (регистрация.сборка.идентификаторРепозитория, репозиторийСборки),
      ] {
        let являетсяГолым =
          try выводГит(
            ["rev-parse", "--is-bare-repository"],
            в: репозиторий,
            исполняемыйФайл: контекст.исполняемыйФайлГит
          ) == "true"
        if !являетсяГолым {
          добавить(
            код: "репозиторий_не_является_голым",
            путь: путьДиагностики("контекст/репозитории/\(идентификатор)"),
            сообщение: "Контекст должен связывать идентификатор с локальным bare-репозиторием.",
            в: &нарушения
          )
        }
      }
      let снимокОтделён =
        try символическаяСсылка(
          в: контекст.снимокИсполнителя,
          исполняемыйФайл: контекст.исполняемыйФайлГит
        ) == nil
      let снимокЧист = try выводГит(
        ["status", "--porcelain=v1", "--untracked-files=all"],
        в: контекст.снимокИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      ).isEmpty
      let объектСнимкаВЧекауте = try выводГит(
        ["rev-parse", "HEAD"],
        в: контекст.снимокИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let снимокСовпадаетСПринятым =
        объектСнимкаВЧекауте
        == исполнитель.идентификаторСнимка
      let путьСуперпроекта = try выводГит(
        ["rev-parse", "--show-superproject-working-tree"],
        в: контекст.снимокИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let относительныйПутьСнимка = относительныйПуть(
        контекст.снимокИсполнителя,
        внутри: контекст.чекаутСборки
      )
      let объектСборочногоЧекаута = try выводГит(
        ["rev-parse", "HEAD"],
        в: контекст.чекаутСборки,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let снимокПринадлежитСборочномуЧекауту =
        !путьСуперпроекта.isEmpty
        && каноническийПуть(URL(fileURLWithPath: путьСуперпроекта, isDirectory: true))
          == каноническийПуть(контекст.чекаутСборки)
        && относительныйПутьСнимка == исполнитель.путьПодмодуля
        && объектСборочногоЧекаута == контекст.идентификаторСнимкаСборки
      let общийКаталогСнимка = try общийКаталогГит(
        контекст.снимокИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let общийКаталогПисателя = try общийКаталогГит(
        контекст.пишущийКлонИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let пишущийКлонОтдельный =
        общийКаталогСнимка != общийКаталогПисателя
        && каноническийПуть(контекст.снимокИсполнителя)
          != каноническийПуть(контекст.пишущийКлонИсполнителя)
      let веткаПисателя = try символическаяСсылка(
        в: контекст.пишущийКлонИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let объектРабочейВетки = try? выводГит(
        ["rev-parse", исполнитель.рабочаяСсылка],
        в: репозиторийИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let объектПисателя = try выводГит(
        ["rev-parse", "HEAD"],
        в: контекст.пишущийКлонИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let рабочаяВеткаСовпадает =
        веткаПисателя == исполнитель.рабочаяСсылка
        && объектРабочейВетки == исполнитель.идентификаторСнимка
        && объектПисателя == объектРабочейВетки

      let объектЖивойСсылкиСборки = try выводГит(
        ["rev-parse", регистрация.сборка.живаяСсылка],
        в: репозиторийСборки,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      if объектЖивойСсылкиСборки != контекст.идентификаторСнимкаСборки {
        добавить(
          код: "живая_ветка_сборки_не_совпадает",
          путь: путьДиагностики("сборка/живая_ссылка"),
          сообщение: "Живая ветка сборки должна точно фиксировать проверяемый снимок сборки.",
          в: &нарушения
        )
      }

      let объектЗеркала = try выводГит(
        ["rev-parse", регистрация.ядро.зеркальнаяСсылка],
        в: репозиторийИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let объектЯдра = try выводГит(
        ["rev-parse", регистрация.ядро.зеркальнаяСсылка],
        в: репозиторийЯдра,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let зеркальнаяВеткаСовпадаетСЯдром =
        объектЗеркала == объектЯдра
        && объектЯдра == регистрация.ядро.опубликованноеПоколение
      let снимокПроисходитОтПоколенияЯдра = try являетсяПредком(
        регистрация.ядро.опубликованноеПоколение,
        потомок: исполнитель.идентификаторСнимка,
        в: репозиторийИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )

      let данныеПаспорта = try? данныеГит(
        [
          "show",
          "\(исполнитель.идентификаторСнимка):\(исполнитель.путьПаспортаРебёнка)",
        ],
        в: репозиторийИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let сыройПаспорт: [String: Any]? = данныеПаспорта.flatMap { данные in
        guard let объект = try? JSONSerialization.jsonObject(with: данные)
        else {
          return nil
        }
        return объект as? [String: Any]
      }
      let сыроеУправление =
        сыройПаспорт?["управляющая_плоскость"]
        as? [String: Any]
      let путьОчереди = сыроеУправление?["путь_очереди"] as? String
      let путьСелектора = сыроеУправление?["путь_селектора"] as? String
      let путьРабочегоНабора = сыроеУправление?["путь_рабочего_набора"] as? String
      let управляющиеПути = [путьОчереди, путьСелектора, путьРабочегоНабора]
        .compactMap { $0 }
      let путиНавыков = [путьОчереди, путьСелектора]
        .compactMap { $0.flatMap(путьНавыкаДляСкрипта) }
      let обязательныеПути =
        [исполнитель.путьПаспортаРебёнка, "AGENTS.md"]
        + управляющиеПути + путиНавыков
      let дочерниеКонтрактыНайдены =
        данныеПаспорта != nil
        && управляющиеПути.count == 3
        && путиНавыков.count == 2
        && обязательныеПути.allSatisfy {
          существуетОбъект(
            "\(исполнитель.идентификаторСнимка):\($0)",
            в: репозиторийИсполнителя,
            исполняемыйФайл: контекст.исполняемыйФайлГит
          )
        }

      let проверкаГит = ПроверкаГитУниверсальногоФоркИсполнителя(
        снимокОтделён: снимокОтделён,
        снимокЧист: снимокЧист,
        снимокСовпадаетСПринятым: снимокСовпадаетСПринятым,
        пишущийКлонОтдельный: пишущийКлонОтдельный,
        рабочаяВеткаСовпадает: рабочаяВеткаСовпадает,
        зеркальнаяВеткаСовпадаетСЯдром: зеркальнаяВеткаСовпадаетСЯдром,
        снимокПроисходитОтПоколенияЯдра: снимокПроисходитОтПоколенияЯдра,
        дочерниеКонтрактыНайдены: дочерниеКонтрактыНайдены
      )

      if !снимокОтделён {
        добавить(
          код: "снимок_не_отделён",
          путь: путьДиагностики("исполнитель/путь_подмодуля"),
          сообщение: "Checkout снимка должен иметь отделённый HEAD.",
          в: &нарушения
        )
      }
      if !снимокЧист {
        добавить(
          код: "снимок_нечист",
          путь: путьДиагностики("исполнитель/путь_подмодуля"),
          сообщение: "Checkout снимка должен быть неизменённым.",
          в: &нарушения
        )
      }
      if !снимокСовпадаетСПринятым {
        добавить(
          код: "чекаут_не_совпадает_с_принятым_снимком",
          путь: путьДиагностики("исполнитель/идентификатор_снимка"),
          сообщение: "Detached-checkout должен точно совпадать с принятым gitlink.",
          в: &нарушения
        )
      }
      if !снимокПринадлежитСборочномуЧекауту {
        добавить(
          код: "снимок_не_принадлежит_сборочному_чекауту",
          путь: путьДиагностики("исполнитель/путь_подмодуля"),
          сообщение:
            "Материализованный снимок должен находиться по точному пути принятого checkout сборки.",
          в: &нарушения
        )
      }
      if !пишущийКлонОтдельный {
        добавить(
          код: "снимок_использован_как_пишущий_клон",
          путь: путьДиагностики("исполнитель"),
          сообщение: "Пишущий клон обязан иметь отдельный Git common-dir.",
          в: &нарушения
        )
      }
      if !рабочаяВеткаСовпадает {
        добавить(
          код: "рабочая_ветка_не_совпадает",
          путь: путьДиагностики("исполнитель/рабочая_ссылка"),
          сообщение: "Пишущий клон и bare fork должны указывать на принятую рабочую ветку.",
          в: &нарушения
        )
      }
      if !зеркальнаяВеткаСовпадаетСЯдром {
        let ядроЯвляетсяПредкомЗеркала = try являетсяПредком(
          регистрация.ядро.опубликованноеПоколение,
          потомок: объектЗеркала,
          в: репозиторийИсполнителя,
          исполняемыйФайл: контекст.исполняемыйФайлГит
        )
        добавить(
          код: ядроЯвляетсяПредкомЗеркала
            ? "зеркальная_ветка_содержит_локальный_коммит"
            : "зеркальная_ветка_расходится_с_ядром",
          путь: путьДиагностики("ядро/зеркальная_ссылка"),
          сообщение: "Зеркальная ветка fork должна точно совпадать с опубликованным ядром.",
          в: &нарушения
        )
      }
      if !снимокПроисходитОтПоколенияЯдра {
        добавить(
          код: "снимок_вне_синхронизированной_основы",
          путь: путьДиагностики("исполнитель/идентификатор_снимка"),
          сообщение: "Принятый снимок должен происходить от опубликованного поколения ядра.",
          в: &нарушения
        )
      }
      if !дочерниеКонтрактыНайдены {
        добавить(
          код: данныеПаспорта == nil
            ? "паспорт_ребёнка_отсутствует" : "дочерние_контракты_отсутствуют",
          путь: путьДиагностики("исполнитель/путь_паспорта_ребёнка"),
          сообщение: "Принятый снимок должен содержать паспорт и управляющие контракты.",
          в: &нарушения
        )
      }

      проверитьУдалённыеРепозитории(
        регистрация,
        репозиторийЯдра: репозиторийЯдра,
        репозиторийИсполнителя: репозиторийИсполнителя,
        репозиторийСборки: репозиторийСборки,
        контекст: контекст,
        нарушения: &нарушения
      )
      проверитьГитлинкСборки(
        регистрация,
        репозиторийСборки: репозиторийСборки,
        контекст: контекст,
        нарушения: &нарушения
      )
      проверитьОтсутствиеГитлинкаВЯдре(
        регистрация,
        репозиторийЯдра: репозиторийЯдра,
        контекст: контекст,
        нарушения: &нарушения
      )

      var паспорт: ПаспортУниверсальногоФоркИсполнителя?
      var сырьёПаспорта: [String: Any]?
      if let данныеПаспорта {
        if хэш(данныеПаспорта) != исполнитель.хэшПаспортаРебёнка {
          добавить(
            код: "паспорт_ребёнка_не_совпадает",
            путь: путьДиагностики("исполнитель/хэш_паспорта_ребёнка"),
            сообщение: "Хэш паспорта не совпадает с байтами принятого снимка.",
            в: &нарушения
          )
        }
        сырьёПаспорта = проверитьСтруктуруПаспорта(
          данныеПаспорта,
          нарушения: &нарушения
        )
        паспорт = try? JSONDecoder().decode(
          ПаспортУниверсальногоФоркИсполнителя.self,
          from: данныеПаспорта
        )
        if паспорт == nil {
          добавить(
            код: "неверный_паспорт_ребёнка",
            путь: путьДиагностики("исполнитель/путь_паспорта_ребёнка"),
            сообщение: "Паспорт ребёнка не соответствует типизированному контракту v2.",
            в: &нарушения
          )
        }
      }

      var идентификаторРоли: String?
      if let паспорт {
        идентификаторРоли = паспорт.контекстнаяРоль.идентификатор
        проверитьПаспорт(
          паспорт,
          сырьё: сырьёПаспорта,
          регистрация: регистрация,
          контекст: контекст,
          нарушения: &нарушения
        )
      }
      проверитьЦиклы(
        регистрация,
        репозиторийИсполнителя: репозиторийИсполнителя,
        репозиторийСборки: репозиторийСборки,
        контекст: контекст,
        нарушения: &нарушения
      )

      return отчёт(
        нарушения: нарушения,
        проверкаГит: проверкаГит,
        регистрация: регистрация,
        идентификаторРоли: идентификаторРоли
      )
    } catch {
      добавить(
        код: "ошибка_системы_версий",
        путь: "",
        сообщение: "Локальная проверка Git завершилась закрытым отказом: \(error)",
        в: &нарушения
      )
      return отчёт(нарушения: нарушения, регистрация: регистрация)
    }
  }

  private static func проверитьУдалённыеРепозитории(
    _ регистрация: РегистрацияУниверсальногоФоркИсполнителя,
    репозиторийЯдра: URL,
    репозиторийИсполнителя: URL,
    репозиторийСборки: URL,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя,
    нарушения: inout [НарушениеПроверкиУниверсальногоФоркИсполнителя]
  ) {
    do {
      let исходныйАдрес = try выводГит(
        ["remote", "get-url", "origin"],
        в: контекст.пишущийКлонИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let вышестоящийАдрес = try выводГит(
        ["remote", "get-url", "upstream"],
        в: контекст.пишущийКлонИсполнителя,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      let исходныйПуть = каноническийПутьРепозитория(
        исходныйАдрес,
        относительно: контекст.пишущийКлонИсполнителя
      )
      let вышестоящийПуть = каноническийПутьРепозитория(
        вышестоящийАдрес,
        относительно: контекст.пишущийКлонИсполнителя
      )
      if исходныйПуть == вышестоящийПуть {
        добавить(
          код: "совпадающие_адреса_репозиториев",
          путь: путьДиагностики("исполнитель/адрес_репозитория"),
          сообщение: "Fork и upstream должны быть разными репозиториями.",
          в: &нарушения
        )
      }
      if исходныйПуть != каноническийПуть(репозиторийИсполнителя) {
        добавить(
          код: "неверный_репозиторий_исполнителя",
          путь: путьДиагностики("исполнитель/адрес_репозитория"),
          сообщение: "Remote origin не совпадает с зарегистрированным fork.",
          в: &нарушения
        )
      }
      if вышестоящийПуть != каноническийПуть(репозиторийЯдра) {
        добавить(
          код: "неверный_репозиторий_ядра",
          путь: путьДиагностики("исполнитель/идентификатор_вышестоящего_репозитория"),
          сообщение: "Remote upstream не совпадает с зарегистрированным ядром.",
          в: &нарушения
        )
      }
      if исходныйПуть == каноническийПуть(репозиторийСборки)
        || вышестоящийПуть == каноническийПуть(репозиторийСборки)
      {
        добавить(
          код: "сборка_использована_как_remote",
          путь: путьДиагностики("исполнитель"),
          сообщение: "Репозиторий сборки не может заменять fork или upstream.",
          в: &нарушения
        )
      }
    } catch {
      добавить(
        код: "удалённые_репозитории_не_проверены",
        путь: путьДиагностики("исполнитель"),
        сообщение: "Не удалось доказать адреса origin и upstream: \(error)",
        в: &нарушения
      )
    }
  }

  private static func проверитьГитлинкСборки(
    _ регистрация: РегистрацияУниверсальногоФоркИсполнителя,
    репозиторийСборки: URL,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя,
    нарушения: inout [НарушениеПроверкиУниверсальногоФоркИсполнителя]
  ) {
    do {
      let рёбра = try рёбраПодмодулей(
        репозиторий: репозиторийСборки,
        объект: контекст.идентификаторСнимкаСборки,
        контекст: контекст
      )
      let соответствующиеПути = рёбра.filter {
        $0.путь == регистрация.исполнитель.путьПодмодуля
      }
      guard соответствующиеПути.count == 1,
        let ребро = соответствующиеПути.first,
        ребро.идентификатор == регистрация.исполнитель.идентификаторРепозитория
      else {
        добавить(
          код: "сборочная_секция_подмодуля_не_совпадает",
          путь: путьДиагностики("исполнитель/путь_подмодуля"),
          сообщение:
            "Снимок сборки должен иметь ровно одну полную секцию .gitmodules для точного пути и репозитория ребёнка.",
          в: &нарушения
        )
        return
      }
      if ребро.объект != регистрация.исполнитель.идентификаторСнимка {
        добавить(
          код: "гитлинк_сборки_не_совпадает",
          путь: путьДиагностики("исполнитель/идентификатор_снимка"),
          сообщение: "Gitlink сборки не фиксирует зарегистрированный снимок исполнителя.",
          в: &нарушения
        )
      }
    } catch {
      добавить(
        код: "сборочная_секция_подмодуля_не_доказана",
        путь: путьДиагностики("исполнитель/путь_подмодуля"),
        сообщение:
          "Не удалось закрыто доказать секцию .gitmodules и гитлинк исполнителя в снимке сборки: \(error)",
        в: &нарушения
      )
    }
  }

  private static func проверитьОтсутствиеГитлинкаВЯдре(
    _ регистрация: РегистрацияУниверсальногоФоркИсполнителя,
    репозиторийЯдра: URL,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя,
    нарушения: inout [НарушениеПроверкиУниверсальногоФоркИсполнителя]
  ) {
    do {
      let дерево = try выводГит(
        ["ls-tree", "-r", регистрация.ядро.опубликованноеПоколение],
        в: репозиторийЯдра,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
      if дерево.split(separator: "\n").contains(where: { $0.hasPrefix("160000 ") }) {
        добавить(
          код: "ядро_содержит_гитлинк",
          путь: путьДиагностики("ядро"),
          сообщение: "Самодостаточное ядро не должно содержать подмодули.",
          в: &нарушения
        )
      }
    } catch {
      добавить(
        код: "ядро_не_проверено",
        путь: путьДиагностики("ядро"),
        сообщение: "Не удалось проверить дерево опубликованного ядра.",
        в: &нарушения
      )
    }
  }

  private static func проверитьСтруктуруПаспорта(
    _ данные: Data,
    нарушения: inout [НарушениеПроверкиУниверсальногоФоркИсполнителя]
  ) -> [String: Any]? {
    var обнаружитель = JSONDuplicateKeyDetector(data: данные)
    do {
      for путь in try обнаружитель.scan() {
        добавить(
          код: "повторный_ключ",
          путь: путьДиагностики("паспорт\(путь)"),
          сообщение: "JSON-объект паспорта содержит повторный ключ.",
          в: &нарушения
        )
      }
    } catch {
      добавить(
        код: "неверный_паспорт_ребёнка",
        путь: путьДиагностики("паспорт"),
        сообщение: "Паспорт ребёнка не является завершённым ограниченным JSON-объектом.",
        в: &нарушения
      )
    }
    guard данные.count <= предельныйРазмерКонвертаУниверсальногоФоркИсполнителя,
      let корень = (try? JSONSerialization.jsonObject(with: данные)) as? [String: Any]
    else {
      добавить(
        код: "неверный_паспорт_ребёнка",
        путь: путьДиагностики("исполнитель/путь_паспорта_ребёнка"),
        сообщение: "Паспорт ребёнка должен быть ограниченным JSON-объектом.",
        в: &нарушения
      )
      return nil
    }
    проверитьЗакрытыйОбъект(
      корень,
      ключи: корневыеКлючиПаспорта,
      путь: путьДиагностики("паспорт"),
      нарушения: &нарушения
    )
    let вложенные: [(String, Set<String>)] = [
      ("универсальный_профиль", ключиПрофиля),
      ("контекстная_роль", ключиРоли),
      ("полномочия", ключиПолномочий),
      ("репозиторная_плоскость", ключиРепозиторнойПлоскости),
      ("управляющая_плоскость", ключиУправляющейПлоскости),
    ]
    for (имя, ключи) in вложенные {
      guard let объект = корень[имя] as? [String: Any] else {
        добавить(
          код: "неверный_тип",
          путь: путьДиагностики("паспорт/\(имя)"),
          сообщение: "Поле паспорта должно быть объектом.",
          в: &нарушения
        )
        continue
      }
      проверитьЗакрытыйОбъект(
        объект,
        ключи: ключи,
        путь: путьДиагностики("паспорт/\(имя)"),
        нарушения: &нарушения
      )
      if имя == "полномочия",
        let цели = объект["разрешённые_цели_запроса_слияния"] as? [[String: Any]]
      {
        for (номер, цель) in цели.enumerated() {
          проверитьЗакрытыйОбъект(
            цель,
            ключи: ключиЦелиСлияния,
            путь: путьДиагностики("паспорт/полномочия/разрешённые_цели_запроса_слияния/\(номер)"),
            нарушения: &нарушения
          )
        }
      }
    }
    return корень
  }

  private static func проверитьПаспорт(
    _ паспорт: ПаспортУниверсальногоФоркИсполнителя,
    сырьё: [String: Any]?,
    регистрация: РегистрацияУниверсальногоФоркИсполнителя,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя,
    нарушения: inout [НарушениеПроверкиУниверсальногоФоркИсполнителя]
  ) {
    let исполнитель = регистрация.исполнитель
    let идентификаторы: [(String, String)] = [
      (паспорт.идентификаторПаспорта, путьДиагностики("паспорт/идентификатор_паспорта")),
      (паспорт.идентификаторРебёнка, путьДиагностики("паспорт/идентификатор_ребёнка")),
      (паспорт.идентификаторРепозитория, путьДиагностики("паспорт/идентификатор_репозитория")),
      (паспорт.идентификаторЯдра, путьДиагностики("паспорт/идентификатор_ядра")),
      (паспорт.идентификаторКомпозиции, путьДиагностики("паспорт/идентификатор_композиции")),

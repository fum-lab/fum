  public let хэшПолномочий: String?
  public let идентификаторРоли: String?
  public let поколениеНазначения: String?

  public var кодыНарушений: Set<String> {
    Set(нарушения.map(\.код))
  }

  fileprivate init(
    нарушения: [НарушениеПроверкиУниверсальногоФоркИсполнителя],
    проверкаГит: ПроверкаГитУниверсальногоФоркИсполнителя?,
    идентификаторРебёнка: String?,
    идентификаторРепозитория: String?,
    идентификаторПрофиля: String?,
    хэшПолномочий: String?,
    идентификаторРоли: String?,
    поколениеНазначения: String?
  ) {
    let упорядоченные = Array(Set(нарушения)).sorted {
      if $0.код != $1.код { return $0.код < $1.код }
      if $0.путь != $1.путь { return $0.путь < $1.путь }
      return $0.сообщение < $1.сообщение
    }
    self.решение = упорядоченные.isEmpty ? .допустимо : .недопустимо
    self.нарушения = упорядоченные
    self.проверкаГит = проверкаГит
    self.идентификаторРебёнка = идентификаторРебёнка
    self.идентификаторРепозитория = идентификаторРепозитория
    self.идентификаторПрофиля = идентификаторПрофиля
    self.хэшПолномочий = хэшПолномочий
    self.идентификаторРоли = идентификаторРоли
    self.поколениеНазначения = поколениеНазначения
  }
}


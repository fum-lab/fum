  private static func проверитьЦиклы(
    _ регистрация: РегистрацияУниверсальногоФоркИсполнителя,
    репозиторийИсполнителя: URL,
    репозиторийСборки: URL,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя,
    нарушения: inout [НарушениеПроверкиУниверсальногоФоркИсполнителя]
  ) {
    let идентификаторИсполнителя = регистрация.исполнитель.идентификаторРепозитория
    let идентификаторСборки = регистрация.сборка.идентификаторРепозитория
    do {
      let циклы = try обнаружитьЦиклы(
        начальныйУзел: УзелГрафаПодмодулей(
          идентификаторРепозитория: идентификаторСборки,
          объект: контекст.идентификаторСнимкаСборки
        ),
        контекст: контекст
      )
      var коды: Set<String> = []
      for цикл in циклы {
        let кольцо = Array(цикл.dropLast())
        let множество = Set(кольцо)
        let код: String
        if кольцо.count == 1 && кольцо.first == идентификаторИсполнителя {
          код = "самоссылочный_снимок"
        } else if множество.contains(идентификаторИсполнителя)
          && множество.contains(идентификаторСборки)
        {
          код =
            кольцо.count == 2
            ? "прямой_цикл_репозиториев" : "транзитивный_цикл_репозиториев"
        } else if множество.contains(идентификаторИсполнителя) {
          код = "транзитивный_возврат_к_ребёнку"
        } else {
          код = "цикл_вложенных_репозиториев"
        }
        коды.insert(код)
      }
      for код in коды.sorted() {
        добавить(
          код: код,
          путь: путьДиагностики("исполнитель/идентификатор_снимка"),
          сообщение: "В материализованном графе репозиториев обнаружен цикл идентичностей.",
          в: &нарушения
        )
      }
    } catch {
      добавить(
        код: "граф_подмодулей_не_проверен",
        путь: путьДиагностики("исполнитель/идентификатор_снимка"),
        сообщение: "Не удалось проверить фактический граф подмодулей: \(error)",
        в: &нарушения
      )
    }
    _ = репозиторийИсполнителя
    _ = репозиторийСборки
  }

  private struct УзелГрафаПодмодулей: Hashable {
    let идентификаторРепозитория: String
    let объект: String
  }

  private struct РеброПодмодуля {
    let идентификатор: String
    let объект: String
    let путь: String
  }

  private static func обнаружитьЦиклы(
    начальныйУзел: УзелГрафаПодмодулей,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя
  ) throws -> [[String]] {
    let пределУникальныхУзлов = 4_096
    let пределУникальныхРёбер = 16_384
    let пределКонтекстныхПереходов = 262_144
    var кэшРёбер: [УзелГрафаПодмодулей: [РеброПодмодуля]] = [:]
    var числоУникальныхРёбер = 0
    var числоКонтекстныхПереходов = 0
    var путь: [String] = []
    var позиции: [String: Int] = [:]
    var циклы: [[String]] = []

    func рёбра(
      _ узел: УзелГрафаПодмодулей,
      репозиторий: URL
    ) throws -> [РеброПодмодуля] {
      if let готовые = кэшРёбер[узел] { return готовые }
      guard кэшРёбер.count < пределУникальныхУзлов else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Граф превысил бюджет уникальных узлов \(пределУникальныхУзлов)."
        )
      }
      let найденные = try рёбраПодмодулей(
        репозиторий: репозиторий,
        объект: узел.объект,
        контекст: контекст
      )
      guard числоУникальныхРёбер <= пределУникальныхРёбер - найденные.count else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Граф превысил бюджет уникальных рёбер \(пределУникальныхРёбер)."
        )
      }
      числоУникальныхРёбер += найденные.count
      кэшРёбер[узел] = найденные
      return найденные
    }

    func посетить(_ узел: УзелГрафаПодмодулей) throws {
      guard
        let репозиторий = контекст.репозиторииПоИдентификатору[
          узел.идентификаторРепозитория
        ]
      else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Не найден локальный репозиторий \(узел.идентификаторРепозитория)."
        )
      }
      позиции[узел.идентификаторРепозитория] = путь.count
      путь.append(узел.идентификаторРепозитория)
      let исходящиеРёбра = try рёбра(узел, репозиторий: репозиторий)
      guard
        числоКонтекстныхПереходов
          <= пределКонтекстныхПереходов - исходящиеРёбра.count
      else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Граф превысил бюджет контекстных переходов \(пределКонтекстныхПереходов)."
        )
      }
      числоКонтекстныхПереходов += исходящиеРёбра.count
      for ребро in исходящиеРёбра {
        if let начало = позиции[ребро.идентификатор] {
          циклы.append(Array(путь[начало...]) + [ребро.идентификатор])
          continue
        }
        try посетить(
          УзелГрафаПодмодулей(
            идентификаторРепозитория: ребро.идентификатор,
            объект: ребро.объект
          )
        )
      }
      _ = путь.popLast()
      позиции.removeValue(forKey: узел.идентификаторРепозитория)
    }

    try посетить(начальныйУзел)
    return циклы
  }

  private static func рёбраПодмодулей(
    репозиторий: URL,
    объект: String,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя
  ) throws -> [РеброПодмодуля] {
    let дерево = try выводГит(
      ["-c", "core.quotePath=false", "ls-tree", "-r", объект],
      в: репозиторий,
      исполняемыйФайл: контекст.исполняемыйФайлГит
    )
    var гитлинки: [String: String] = [:]
    for строка in дерево.split(separator: "\n") {
      guard let разделитель = строка.firstIndex(of: "\t") else { continue }
      let метаданные = строка[..<разделитель].split(separator: " ")
      guard метаданные.count == 3, метаданные[0] == "160000" else { continue }
      let путь = String(строка[строка.index(after: разделитель)...])
      guard гитлинки[путь] == nil else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Дерево содержит повторный путь гитлинка \(путь)."
        )
      }
      гитлинки[путь] = String(метаданные[2])
    }

    let модули: String
    do {
      модули = try выводГит(
        ["show", "\(объект):.gitmodules"],
        в: репозиторий,
        исполняемыйФайл: контекст.исполняемыйФайлГит
      )
    } catch {
      guard гитлинки.isEmpty else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Дерево содержит гитлинк без файла .gitmodules."
        )
      }
      return []
    }

    struct РазделПодмодуля {
      let имя: String
      var путь: String?
      var адрес: String?
    }
    var разделы: [РазделПодмодуля] = []
    var текущийРаздел: РазделПодмодуля?
    for исходнаяСтрока in модули.split(separator: "\n", omittingEmptySubsequences: false) {
      let строка = исходнаяСтрока.trimmingCharacters(in: .whitespaces)
      if строка.isEmpty || строка.hasPrefix("#") || строка.hasPrefix(";") {
        continue
      }
      if строка.hasPrefix("[submodule \"") && строка.hasSuffix("\"]") {
        if let текущийРаздел { разделы.append(текущийРаздел) }
        let началоИмени = строка.index(строка.startIndex, offsetBy: 12)
        let конецИмени = строка.index(строка.endIndex, offsetBy: -2)
        let имя = String(строка[началоИмени..<конецИмени])
        guard !имя.isEmpty else {
          throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
            "Раздел .gitmodules имеет пустое имя."
          )
        }
        текущийРаздел = РазделПодмодуля(имя: имя, путь: nil, адрес: nil)
        continue
      }
      let части = строка.split(separator: "=", maxSplits: 1).map {
        $0.trimmingCharacters(in: .whitespaces)
      }
      guard части.count == 2, var раздел = текущийРаздел else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Параметр .gitmodules находится вне полного раздела подмодуля."
        )
      }
      switch части[0] {
      case "path":
        guard раздел.путь == nil, !части[1].isEmpty else {
          throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
            "Раздел \(раздел.имя) имеет повторный или пустой path."
          )
        }
        раздел.путь = части[1]
      case "url":
        guard раздел.адрес == nil, !части[1].isEmpty else {
          throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
            "Раздел \(раздел.имя) имеет повторный или пустой url."
          )
        }
        раздел.адрес = части[1]
      default:
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Раздел \(раздел.имя) содержит неизвестный ключ \(части[0])."
        )
      }
      текущийРаздел = раздел
    }
    if let текущийРаздел { разделы.append(текущийРаздел) }
    guard Set(разделы.map(\.имя)).count == разделы.count else {
      throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
        "Файл .gitmodules содержит повторное имя раздела."
      )
    }

    var результат: [РеброПодмодуля] = []
    var путиРазделов: Set<String> = []
    for раздел in разделы {
      guard let путь = раздел.путь, let адрес = раздел.адрес,
        let объектГитлинка = гитлинки[путь]
      else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Раздел \(раздел.имя) не имеет согласованной пары path, url и гитлинка: "
            + "path=\(раздел.путь ?? "<нет>"), url=\(раздел.адрес ?? "<нет>"), "
            + "гитлинки=\(гитлинки.keys.sorted())."
        )
      }
      guard путиРазделов.insert(путь).inserted else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Несколько разделов .gitmodules ссылаются на путь \(путь)."
        )
      }
      let путьРепозитория = каноническийПутьРепозитория(
        адрес,
        относительно: репозиторий
      )
      let совпавшиеРепозитории = контекст.репозиторииПоИдентификатору.filter {
        каноническийПуть($0.value) == путьРепозитория
      }
      guard совпавшиеРепозитории.count == 1,
        let идентификатор = совпавшиеРепозитории.first?.key
      else {
        throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
          "Адрес \(адрес) не сопоставлен ровно одному известному репозиторию."
        )
      }
      результат.append(
        РеброПодмодуля(
          идентификатор: идентификатор,
          объект: объектГитлинка,
          путь: путь
        )
      )
    }
    guard путиРазделов == Set(гитлинки.keys) else {
      throw ОшибкаГрафаПодмодулей.недоказанноеРебро(
        "Не каждый гитлинк дерева имеет ровно один полный раздел .gitmodules."
      )
    }
    return результат
  }

  private static func проверитьЗакрытыйОбъект(

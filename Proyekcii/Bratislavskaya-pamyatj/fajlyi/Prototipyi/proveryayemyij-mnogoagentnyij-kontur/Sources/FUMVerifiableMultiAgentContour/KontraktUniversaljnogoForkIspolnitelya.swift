private let предельныйРазмерКонвертаУниверсальногоФоркИсполнителя = 1_048_576

public enum ОшибкаСхемУниверсальногоФоркИсполнителя: Error, CustomStringConvertible, Sendable {
  case ресурсОтсутствует(String)
  case ресурсСлишкомВелик(String, Int)

  public var description: String {
    switch self {
    case .ресурсОтсутствует(let имя):
      "Не найдена схема универсального fork-исполнителя: \(имя)."
    case .ресурсСлишкомВелик(let имя, let размер):
      "Схема универсального fork-исполнителя \(имя) превышает предел: \(размер)."
    }
  }
}

public enum СхемыУниверсальногоФоркИсполнителя {
  public static func загрузитьРегистрацию() throws -> Data {
    try загрузить(
      имя: "схема-регистрации-универсального-форк-исполнителя-v2"
    )
  }

  public static func загрузитьПаспортРебёнка() throws -> Data {
    try загрузить(
      имя: "схема-паспорта-универсального-форк-исполнителя-v2"
    )
  }

  private static func загрузить(имя: String) throws -> Data {
    let адрес =
      Bundle.module.url(
        forResource: имя,
        withExtension: "json",
        subdirectory: "Фикстуры/РепозиторнаяКомпозиция"
      )
      ?? Bundle.module.url(
        forResource: имя,
        withExtension: "json",
        subdirectory: "РепозиторнаяКомпозиция"
      )
      ?? Bundle.module.url(forResource: имя, withExtension: "json")
    guard let адрес else {
      throw ОшибкаСхемУниверсальногоФоркИсполнителя.ресурсОтсутствует(имя)
    }
    let значения = try адрес.resourceValues(forKeys: [.fileSizeKey])
    guard let размер = значения.fileSize,
      размер <= предельныйРазмерКонвертаУниверсальногоФоркИсполнителя
    else {
      throw ОшибкаСхемУниверсальногоФоркИсполнителя.ресурсСлишкомВелик(
        имя,
        значения.fileSize ?? -1
      )
    }
    let данные = try Data(contentsOf: адрес, options: [.mappedIfSafe])
    guard данные.count <= предельныйРазмерКонвертаУниверсальногоФоркИсполнителя else {
      throw ОшибкаСхемУниверсальногоФоркИсполнителя.ресурсСлишкомВелик(
        имя,
        данные.count
      )
    }
    return данные
  }
}


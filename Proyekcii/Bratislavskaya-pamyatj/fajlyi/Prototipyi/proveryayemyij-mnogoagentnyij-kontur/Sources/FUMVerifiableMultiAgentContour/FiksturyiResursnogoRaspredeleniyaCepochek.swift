  return [
    .левая: [
      ресурсныеПолномочияКорневойФикстуры(
        идентификатор: левыйИдентификатор,
        областиЗаписи: [
          ОбластьЗаписиРесурсногоНазначения(вид: .поддерево, путь: леваяОбласть)
        ],
        изменяемыеРесурсы: изменяемыеРесурсы,
        настольнаяСреда: "настольная-среда-фикстуры",
        профильМодели: "модель-фикстуры",
        пределы: ПределыРесурсногоНазначения(
          форк: 1,
          назначение: 1,
          ребёнок: 1,
          настольнаяСреда: 4,
          профильМодели: 4
        )
      )
    ],
    .правая: [
      ресурсныеПолномочияКорневойФикстуры(
        идентификатор: правыйИдентификатор,
        областиЗаписи: [
          ОбластьЗаписиРесурсногоНазначения(вид: .поддерево, путь: праваяОбласть)
        ],
        изменяемыеРесурсы: изменяемыеРесурсы,
        настольнаяСреда: "настольная-среда-фикстуры",
        профильМодели: "модель-фикстуры",
        пределы: ПределыРесурсногоНазначения(

public enum ФикстурыРесурсногоРаспределенияЦепочек {
  public static func потерянныйРесурсныйОтветСреды() throws
    -> ИтогПотерянногоРесурсногоОтветаСреды
  {
    let полномочия = стандартныеРесурсныеПолномочияКорневойФикстуры()
    return try ФикстурыКорневогоРеестраЗапусков.сМатериализованнымРесурснымПоколением(
      ресурсныеПолномочия: полномочия
    ) { реестр, ветви in
      let ветвь = try ветвьРесурснойФикстуры(ветви, сторона: .левая)
      let полномочие = try полномочияРесурснойФикстуры(полномочия, сторона: .левая)
      let назначение = структурированноеРесурсноеНазначениеКорневойФикстуры(
        ветвь: ветвь,
        полномочия: полномочие
      )
      let хэшНазначения = try реестр.зарегистрироватьРесурсноеНазначение(назначение)

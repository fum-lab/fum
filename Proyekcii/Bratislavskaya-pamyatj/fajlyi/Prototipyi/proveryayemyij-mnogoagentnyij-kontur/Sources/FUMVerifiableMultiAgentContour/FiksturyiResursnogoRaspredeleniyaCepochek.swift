private final class АвтономнаяПоддельнаяСредаРесурсныхЗапусков: @unchecked Sendable {
  private let блокировка = NSLock()
  private let начала = DispatchSemaphore(value: 0)
  private let разрешения = DispatchSemaphore(value: 0)
  private let завершения = DispatchSemaphore(value: 0)
  private var последовательность = 0
  private var активные = 0
  private var максимум = 0
  private var события: [(номер: Int, вид: String, запуск: String)] = []

  var числоНачал: Int {
    блокировка.withLock { события.count { $0.вид == "начало" } }
  }

  var числоЗавершений: Int {
    блокировка.withLock { события.count { $0.вид == "завершение" } }
  }

  var максимумОдновременныхЗапусков: Int { блокировка.withLock { максимум } }

  func запустить(_ идентификатор: String) {
    DispatchQueue.global().async { [self] in
      добавитьСобытие("начало", запуск: идентификатор)
      блокировка.withLock {
        активные += 1
        максимум = max(максимум, активные)
      }
      начала.signal()
      разрешения.wait()
      блокировка.withLock { активные -= 1 }
      добавитьСобытие("завершение", запуск: идентификатор)
      завершения.signal()
    }
  }

  func ожидатьНачало() { начала.wait() }
  func разрешитьЗавершение() { разрешения.signal() }
  func ожидатьЗавершение() { завершения.wait() }

  func отметитьТерминализацию(_ идентификатор: String) {
    добавитьСобытие("терминализация", запуск: идентификатор)
  }

  func былаЗапущена(_ идентификатор: String) -> Bool {
    блокировка.withLock {
      события.contains { $0.вид == "начало" && $0.запуск == идентификатор }
    }
  }

  func терминализацияРаньшеНачала(первый: String, второй: String) -> Bool {
    блокировка.withLock {
      guard
        let терминализация = события.first(where: {
          $0.вид == "терминализация" && $0.запуск == первый
        }),
        let начало = события.first(where: {
          $0.вид == "начало" && $0.запуск == второй
        })
      else { return false }
      return терминализация.номер < начало.номер
    }
  }

  private func добавитьСобытие(_ вид: String, запуск: String) {
    блокировка.withLock {
      последовательность += 1
      события.append((последовательность, вид, запуск))
    }
  }
}

private func ресурсныеПолномочияПарыФикстуры(

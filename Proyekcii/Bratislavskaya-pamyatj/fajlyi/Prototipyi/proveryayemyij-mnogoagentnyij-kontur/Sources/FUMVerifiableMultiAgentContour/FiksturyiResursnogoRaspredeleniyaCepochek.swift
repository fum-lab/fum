      } catch let ошибка as ОшибкаКорневогоРеестраЗапусков {
        кодПотери = ошибка.код
      }
      let запрос = try среда.запрос(сторона: ветвь.сторона)
      let состояниеДоПерезапуска = try реестр.восстановитьРесурсноеРешение(
        попытка: идентификаторПопытки
      ).состояние
      let идентификаторыДоПерезапуска = try ресурснаяПривязкаСредыСохранена(
        адресРеестра: ветвь.адресРеестра,
        поколение: ветвь.поколение,
        сторона: ветвь.сторона,
        попытка: идентификаторПопытки,
        задача: задача,
        среда: средаЗадачи
      )
      let восстановленный = try КорневойРеестрЗапусков(каталог: ветвь.адресРеестра)
      try восстановленный.восстановитьТочнуюПопытку(
        поколение: ветвь.поколение,
        сторона: ветвь.сторона,
        среда: среда
      )
      let состояниеПослеЧтения = try восстановленный.восстановитьРесурсноеРешение(
        попытка: идентификаторПопытки
      ).состояние
      let идентификаторыПослеЧтения = try ресурснаяПривязкаСредыСохранена(
        адресРеестра: ветвь.адресРеестра,
        поколение: ветвь.поколение,
        сторона: ветвь.сторона,
        попытка: идентификаторПопытки,

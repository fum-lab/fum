        состояниеПослеАвторитетногоЧтения: состояниеПослеЧтения,
        идентификаторыСохраненыДоПерезапуска: идентификаторыДоПерезапуска,
        идентификаторыСохраненыПослеЧтения: идентификаторыПослеЧтения,

private func полномочияРесурснойФикстуры(
  _ полномочия: [СторонаВетвевогоФорка: [КорневыеПолномочияРесурсногоНазначения]],
  сторона: СторонаВетвевогоФорка
) throws -> КорневыеПолномочияРесурсногоНазначения {
  guard let полномочияВетви = полномочия[сторона],
    полномочияВетви.count == 1,
    let единственные = полномочияВетви.first
  else {
    throw ОшибкаКорневогоРеестраЗапусков(
      "ресурсная_фикстура_не_нашла_единственные_полномочия"
    )
  }
  return единственные
}

private func ветвьРесурснойФикстуры(
  _ ветви: [СторонаВетвевогоФорка: МатериализованнаяВетвьКорневойФикстуры],
  сторона: СторонаВетвевогоФорка
) throws -> МатериализованнаяВетвьКорневойФикстуры {
  guard let ветвь = ветви[сторона] else {
    throw ОшибкаКорневогоРеестраЗапусков("ресурсная_фикстура_не_нашла_ветвь")
  }
  return ветвь
}

private func подготовитьДваРесурсныхДопуска(
  реестр: КорневойРеестрЗапусков,
  левое: СтруктурированноеРесурсноеНазначение,
  правое: СтруктурированноеРесурсноеНазначение,
  леваяПопытка: String,
  праваяПопытка: String
) throws -> (РешениеРесурсногоДопуска, РешениеРесурсногоДопуска) {
  _ = try реестр.зарегистрироватьРесурсноеНазначение(левое)
  _ = try реестр.зарегистрироватьРесурсноеНазначение(правое)
  let левыйДопуск = try реестр.запроситьРесурсныйДопуск(
    назначение: левое.идентификатор,
    попытка: леваяПопытка,
    ожидаемыйХэшНазначения: try левое.каноническийХэш()
  )
  let правыйДопуск = try реестр.запроситьРесурсныйДопуск(
    назначение: правое.идентификатор,
    попытка: праваяПопытка,
    ожидаемыйХэшНазначения: try правое.каноническийХэш()
  )
  return (левыйДопуск, правыйДопуск)
}

private func ресурснаяПривязкаСредыСохранена(
  адресРеестра: URL,
  поколение: String,
  сторона: СторонаВетвевогоФорка,
  попытка: String,
  задача: String,
  среда: String
) throws -> Bool {
  let данные = try Data(
    contentsOf: адресРеестра.appendingPathComponent("реестр.json")
  )
  guard let состояние = try JSONSerialization.jsonObject(with: данные) as? [String: Any],
    let поколения = состояние["поколения"] as? [String: Any],
    let записьПоколения = поколения[поколение] as? [String: Any],
    let ветви = записьПоколения["ветви"] as? [String: Any],
    let ветвь = ветви[сторона.rawValue] as? [String: Any],
    let корневаяПопытка = ветвь["попытка"] as? [String: Any],
    let ресурсныеПопытки = состояние["ресурсныеПопытки"] as? [String: Any],
    let ресурснаяПопытка = ресурсныеПопытки[попытка] as? [String: Any]
  else {
    return false
  }
  return корневаяПопытка["идентификаторЗадачи"] as? String == задача
    && корневаяПопытка["идентификаторСреды"] as? String == среда
    && ресурснаяПопытка["идентификаторЗадачи"] as? String == задача
    && ресурснаяПопытка["идентификаторСреды"] as? String == среда
}

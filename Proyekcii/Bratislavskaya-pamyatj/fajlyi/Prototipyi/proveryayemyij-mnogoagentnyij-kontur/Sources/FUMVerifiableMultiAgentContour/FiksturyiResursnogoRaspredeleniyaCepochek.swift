      правыйИдентификатор: "ресурсная-политика-совместимая-Б",
      праваяОбласть: "Документация/совместимая-Б"
    )
    return try ФикстурыКорневогоРеестраЗапусков.сМатериализованнымРесурснымПоколением(
      ресурсныеПолномочия: полномочия
    ) {
      реестр,
      ветви in
      let леваяВетвь = try ветвьРесурснойФикстуры(ветви, сторона: .левая)
      let праваяВетвь = try ветвьРесурснойФикстуры(ветви, сторона: .правая)
      let левое = структурированноеРесурсноеНазначениеКорневойФикстуры(
        ветвь: леваяВетвь,
        полномочия: try полномочияРесурснойФикстуры(полномочия, сторона: .левая)
      )
      let правое = структурированноеРесурсноеНазначениеКорневойФикстуры(
        ветвь: праваяВетвь,
        полномочия: try полномочияРесурснойФикстуры(полномочия, сторона: .правая)

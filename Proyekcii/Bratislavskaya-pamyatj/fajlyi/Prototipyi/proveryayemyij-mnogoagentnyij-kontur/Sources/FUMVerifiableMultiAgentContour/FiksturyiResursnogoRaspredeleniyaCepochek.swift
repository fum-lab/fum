        throw ОшибкаКорневогоРеестраЗапусков(
          "фикстура_не_получила_ресурсный_допуск"
        )
      }
      let задача = "task.resource-lost"
      let средаЗадачи = "host.resource-lost"
      let среда = АвтономнаяПоддельнаяСредаЗадач(исходы: [

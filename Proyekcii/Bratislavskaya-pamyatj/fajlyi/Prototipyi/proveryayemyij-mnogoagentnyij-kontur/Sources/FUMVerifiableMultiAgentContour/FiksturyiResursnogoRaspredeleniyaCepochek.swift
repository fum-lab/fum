        throw ОшибкаКорневогоРеестраЗапусков("совместимые_попытки_не_допущены")
      }
      let среда = АвтономнаяПоддельнаяСредаРесурсныхЗапусков()
      среда.запустить("А")
      среда.запустить("Б")
      среда.ожидатьНачало()
      среда.ожидатьНачало()
      let обаНачались = среда.числоНачал == 2 && среда.числоЗавершений == 0
      среда.разрешитьЗавершение()
      среда.разрешитьЗавершение()
      среда.ожидатьЗавершение()
      среда.ожидатьЗавершение()
      return ИтогСовместимогоРесурсногоПерекрытия(
        максимумОдновременныхЗапусков: среда.максимумОдновременныхЗапусков,
        обаЗапускаНачалисьДоОсвобождения: обаНачались
      )
    }
  }


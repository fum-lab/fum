private func событиеРедуктора(
  _ метка: String,
  _ вид: ВидСобытияПоколенияВетвевыхФорков,
  сторона: СторонаВетвевогоФорка? = nil,
  исходСреды: ИсходПодготовкиСредыВетвевогоФорка? = nil
) -> СобытиеПоколенияВетвевыхФорков {
  let идентификаторПопытки = сторона.map { _ in "попытка.среды.пара" }
  let хэшКомандыПопытки = сторона.map { _ in
    хэшСтрокиДерева("команда-попытки-среды-пара")
  }
  return СобытиеПоколенияВетвевыхФорков(
    идентификатор: "событие.\(метка)",
    хэшКоманды: хэшСтрокиДерева("событие-\(метка)"),
    вид: вид,
    сторона: сторона,
    исходСреды: исходСреды,
    идентификаторПопыткиСреды: вид == .зафиксироватьОтветСреды
      ? идентификаторПопытки : nil,
    хэшКомандыПопыткиСреды: вид == .зафиксироватьОтветСреды
      ? хэшКомандыПопытки : nil
  )
}


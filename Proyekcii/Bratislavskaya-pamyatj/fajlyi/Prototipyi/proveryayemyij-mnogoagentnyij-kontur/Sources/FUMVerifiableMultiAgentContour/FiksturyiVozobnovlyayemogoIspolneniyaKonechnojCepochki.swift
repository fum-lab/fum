  private static func восстановитьДоверенныйКонтекст(
    пакет: [String: Any],
    назначение: [String: Any],
    база: String,
    вершина: String,
    рабочаяКопия: String,
    рабочаяСсылка: String,
    объектФинальнойОчереди: String,
    корень: URL
  ) throws -> КонтекстПроверкиДелегированияКонечнойЦепочки {
    let задачи = ["задача-цепочки-01", "задача-цепочки-02"]
    var допуски: [[String: Any]] = []
    var попытки: [[String: Any]] = []
    var квитанции: [[String: Any]] = []
    var данныеКвитанций: [Data] = []

    for задача in задачи {
      guard
        let (допуск, _) =
          try ИнструментыВозобновляемойЦепочки
          .прочитатьСсылкуСтруктурированныхДанных(
            СборкаЖивогоДиапазонаВозобновляемойЦепочки.ссылкаДопуска(задача),
            корень: корень
          ),
        let (попытка, _) =
          try ИнструментыВозобновляемойЦепочки
          .прочитатьСсылкуСтруктурированныхДанных(
            СборкаЖивогоДиапазонаВозобновляемойЦепочки.ссылкаПопытки(задача),
            корень: корень
          ),
        try строка(попытка, "состояние") == "коммит_подтверждён"
      else {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Не восстановлены exact admission/attempt-свидетельства."
        )
      }
      let ссылкаКвитанции = try строка(попытка, "ссылка_квитанции")
      let объектКвитанции = try строка(попытка, "объект_квитанции")
      let данныеКвитанции = try ИнструментыВозобновляемойЦепочки.данныеГит(
        ["cat-file", "blob", объектКвитанции], корень: корень
      )
      let квитанция = try КодированиеВозобновляемойЦепочки.объект(данныеКвитанции)
      guard
        try ИнструментыВозобновляемойЦепочки.текстГит(
          ["rev-parse", ссылкаКвитанции], корень: корень
        ) == объектКвитанции,
        try строка(квитанция, "идентификатор_задачи") == задача,
        try строка(квитанция, "поколение") == строка(допуск, "поколение"),
        try строка(квитанция, "исходная_вершина") == строка(допуск, "базовая_вершина"),
        try строка(квитанция, "идентификатор_продолжения")
          == строка(попытка, "идентификатор_продолжения")
      else {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Exact receipt не совпала с admission и continuation."
        )
      }
      try СборкаЖивогоДиапазонаВозобновляемойЦепочки.проверитьИсторическийДопускИДочернийБилет(
        допуск: допуск,
        попытка: попытка,
        корень: корень
      )
      допуски.append(допуск)
      попытки.append(попытка)
      квитанции.append(квитанция)
      данныеКвитанций.append(данныеКвитанции)
    }

    let ссылкиКвитанций = попытки.compactMap {
      $0["ссылка_квитанции"] as? String
    }
    let объектыКвитанций = попытки.compactMap {
      $0["объект_квитанции"] as? String
    }
    guard try строка(квитанции[0], "исходная_вершина") == база,
      try строка(квитанции[0], "новая_вершина")
        == строка(квитанции[1], "исходная_вершина"),
      try строка(квитанции[1], "новая_вершина") == вершина,
      (пакет["ссылки_квитанций"] as? [String]) == ссылкиКвитанций,
      (пакет["объекты_квитанций"] as? [String]) == объектыКвитанций
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Доверенные receipt-свидетельства не образуют пакетный диапазон."
      )
    }

    let эпоха =
      "эпоха.локальной-очереди.\(хэш(Data((рабочаяКопия + рабочаяСсылка + база).utf8)).dropFirst("sha256:".count))"
    let переходы = try СборкаЖивогоДиапазонаВозобновляемойЦепочки.построитьПереходы(
      допуски: допуски,
      попытки: попытки,
      квитанции: квитанции,
      данныеКвитанций: данныеКвитанций,
      эпоха: эпоха,
      рабочаяКопия: рабочаяКопия,
      рабочаяСсылка: рабочаяСсылка
    ).свидетельства
    let данныеФинальнойОчереди = try ИнструментыВозобновляемойЦепочки.данныеГит(
      ["cat-file", "blob", объектФинальнойОчереди], корень: корень
    )
    return try СборкаЖивогоДиапазонаВозобновляемойЦепочки.построитьКонтекст(
      назначение: назначение,
      база: база,
      вершина: вершина,
      рабочаяКопия: рабочаяКопия,
      рабочаяСсылка: рабочаяСсылка,
      переходы: переходы,
      эпоха: эпоха,
      хэшОчереди: хэш(данныеФинальнойОчереди),
      корень: корень
    )
  }

  private static func проверитьДоверенныеКорни(
    пакет: [String: Any],
    рабочаяКопия: String,
    рабочаяСсылка: String,
    база: String,
    вершина: String,
    ссылкаНазначения: String,
    объектНазначения: String,
    ссылкаСостояния: String,
    объектСостояния: String,
    ссылкаФинальногоДопуска: String,
    объектФинальногоДопуска: String,
    ссылкаФинальнойОчереди: String,
    объектФинальнойОчереди: String,
    путиПаспортов: [String],
    хэшиПаспортов: [String],
    корень: URL
  ) throws -> Bool {
    let хэшВетки = SHA256.hash(data: Data(рабочаяСсылка.utf8)).map {
      String(format: "%02x", $0)
    }.joined()
    guard
      ссылкаНазначения
        == "refs/fum/назначения-конечных-цепочек/\(рабочаяКопия)/\(хэшВетки)",
      ссылкаСостояния
        == "refs/fum/состояния-конечных-цепочек/\(рабочаяКопия)/\(хэшВетки)",
      try ИнструментыВозобновляемойЦепочки.текстГит(
        ["symbolic-ref", "HEAD"], корень: корень
      ) == рабочаяСсылка
    else { return false }

    for (ссылка, ожидаемыйОбъект) in [
      (ссылкаНазначения, объектНазначения),
      (ссылкаСостояния, объектСостояния),
      (ссылкаФинальногоДопуска, объектФинальногоДопуска),
      (ссылкаФинальнойОчереди, объектФинальнойОчереди),
    ] {
      guard
        try ИнструментыВозобновляемойЦепочки.текстГит(
          ["rev-parse", ссылка], корень: корень
        ) == ожидаемыйОбъект
      else { return false }
    }

    let данныеНазначения = try ИнструментыВозобновляемойЦепочки.данныеГит(
      ["cat-file", "blob", объектНазначения], корень: корень
    )
    let данныеСостояния = try ИнструментыВозобновляемойЦепочки.данныеГит(
      ["cat-file", "blob", объектСостояния], корень: корень
    )
    let назначение = try КодированиеВозобновляемойЦепочки.объект(данныеНазначения)
    let состояние = try КодированиеВозобновляемойЦепочки.объект(данныеСостояния)
    guard try проверитьСамохэш(назначение, поле: "хэш_назначения"),
      try проверитьСамохэш(состояние, поле: "хэш_состояния"),
      try строка(назначение, "хэш_назначения") == строка(пакет, "хэш_назначения"),
      try строка(состояние, "хэш_состояния") == строка(пакет, "хэш_состояния"),
      try строка(назначение, "исходный_коммит") == база,
      try строка(назначение, "идентификатор_физической_рабочей_копии") == рабочаяКопия,
      try строка(назначение, "рабочая_ссылка") == рабочаяСсылка,
      try строка(состояние, "исходный_коммит") == база,
      try строка(состояние, "текущая_вершина") == вершина,
      try строка(состояние, "идентификатор_физической_рабочей_копии") == рабочаяКопия,
      try строка(состояние, "рабочая_ссылка") == рабочаяСсылка,
      try строка(объект(назначение, "корневой_источник"), "поколение")
        == ИнструментыВозобновляемойЦепочки.текстГит(
          ["rev-parse", "refs/heads/master"], корень: корень
        )
    else { return false }

    let нарушенияСхем = try [
      (данныеНазначения, СхемыДелегированияКонечнойЦепочки.загрузитьНазначение()),
      (данныеСостояния, СхемыДелегированияКонечнойЦепочки.загрузитьСостояние()),
    ].flatMap { данные, схема -> [НарушениеЗакрытойСхемы] in
      ПроверкаЗакрытойСхемы.проверитьДокумент(
        try JSONSerialization.jsonObject(with: данные),
        по: схема
      )
    }
    guard нарушенияСхем.isEmpty else { return false }

    guard
      let доверенныйКонтекст = try? восстановитьДоверенныйКонтекст(
        пакет: пакет,
        назначение: назначение,
        база: база,
        вершина: вершина,
        рабочаяКопия: рабочаяКопия,
        рабочаяСсылка: рабочаяСсылка,
        объектФинальнойОчереди: объектФинальнойОчереди,
        корень: корень
      )
    else { return false }
    let семантическийОтчёт = ПроверкаДелегированияКонечнойЦепочки.проверить(
      назначение: данныеНазначения,
      состояние: данныеСостояния,
      контекст: доверенныйКонтекст
    )
    guard семантическийОтчёт.решение == .допустимо else { return false }

    let карточки = try массивОбъектов(назначение, "карточки")
    for карточка in карточки {
      let путь = try строка(карточка, "путь")
      let данныеКарточки = try ИнструментыВозобновляемойЦепочки.данныеГит(
        ["show", "\(база):\(путь)"], корень: корень
      )
      guard хэш(данныеКарточки) == (try строка(карточка, "хэш_содержимого")) else {
        return false
      }
    }
    for поле in ["карточка_цепочки", "рабочий_набор"] {
      let свидетельство = try объект(назначение, поле)
      let путь = try строка(свидетельство, "путь")
      let данныеСвидетельства = try ИнструментыВозобновляемойЦепочки.данныеГит(
        ["show", "\(база):\(путь)"], корень: корень
      )
      guard
        хэш(данныеСвидетельства)
          == (try строка(свидетельство, "хэш_содержимого"))
      else { return false }
    }

    let границы = try объект(назначение, "границы")
    let области = границы["области"] as? [String] ?? []
    let исключения = границы["исключения"] as? [String] ?? []
    let шаги = try массивОбъектов(состояние, "шаги")
    let коммиты = пакет["коммиты"] as? [String] ?? []
    guard шаги.count == 2, коммиты.count == 2 else { return false }
    var суммаТокенов = 0
    var суммаСекунд = 0
    var суммаФайлов = 0
    for индекс in 0..<2 {
      let путьПаспорта = путиПаспортов[индекс]
      let данныеПаспорта = try ИнструментыВозобновляемойЦепочки.данныеГит(
        ["show", "HEAD:\(путьПаспорта)"], корень: корень
      )
      guard хэш(данныеПаспорта) == хэшиПаспортов[индекс] else { return false }
      let паспорт = try КодированиеВозобновляемойЦепочки.объект(данныеПаспорта)
      let частныйПаспорт = try объект(шаги[индекс], "частный_паспорт")
      let путьПакетаШага = try строка(паспорт, "путь_пакета")
      let данныеПакетаШага = try ИнструментыВозобновляемойЦепочки.данныеГит(
        ["show", "HEAD:\(путьПакетаШага)"], корень: корень
      )
      let пакетШага = try КодированиеВозобновляемойЦепочки.объект(данныеПакетаШага)
      let объявленныеПути = пакетШага["объявленные_пути"] as? [String] ?? []
      let предок = индекс == 0 ? база : коммиты[индекс - 1]
      let фактическиеПути = try ИнструментыВозобновляемойЦепочки.данныеГит(
        ["diff", "--no-renames", "--name-only", "-z", предок, коммиты[индекс], "--"],
        корень: корень
      ).split(separator: 0).compactMap { String(data: Data($0), encoding: .utf8) }.sorted()
      guard try строка(частныйПаспорт, "путь") == путьПаспорта,
        try строка(частныйПаспорт, "хэш") == хэш(данныеПаспорта),
        try строка(паспорт, "идентификатор_карточки")
          == строка(шаги[индекс], "идентификатор_карточки"),
        try строка(паспорт, "хэш_карточки") == строка(шаги[индекс], "хэш_карточки"),
        try строка(паспорт, "хэш_пакета") == хэш(данныеПакетаШага),
        объявленныеПути.sorted() == фактическиеПути,
        объявленныеПути.allSatisfy({ путь in
          области.contains(where: { путьСоответствует(путь, шаблону: $0) })
            && !исключения.contains(where: { путьСоответствует(путь, шаблону: $0) })
        })
      else { return false }
      let путьПроверки = try строка(пакетШага, "путь_свидетельства_проверки")
      let данныеПроверки = try ИнструментыВозобновляемойЦепочки.данныеГит(
        ["show", "HEAD:\(путьПроверки)"], корень: корень
      )
      let проверки = try массивОбъектов(паспорт, "проверки")
      guard проверки.count == 1,
        try строка(проверки[0], "исход") == "успешно",
        try строка(проверки[0], "хэш_свидетельства") == хэш(данныеПроверки)
      else { return false }
      суммаТокенов += try целое(паспорт, "токены")
      суммаСекунд += try целое(паспорт, "секунды")
      суммаФайлов += try целое(паспорт, "изменённые_файлы")
    }

    let расход = try объект(состояние, "расход_бюджетов")
    let пределы = try объект(границы, "бюджеты")
    let остаток = try объект(пакет, "остаток_бюджета")
    guard try целое(расход, "токены") == суммаТокенов,
      try целое(расход, "секунды") == суммаСекунд,
      try целое(расход, "изменённые_файлы") == суммаФайлов,
      try целое(остаток, "токены") == целое(пределы, "токены") - суммаТокенов,
      try целое(остаток, "секунды") == целое(пределы, "секунды") - суммаСекунд,
      try целое(остаток, "изменённые_файлы")
        == целое(пределы, "изменённые_файлы") - суммаФайлов
    else { return false }

    let допуск = try КодированиеВозобновляемойЦепочки.объект(
      ИнструментыВозобновляемойЦепочки.данныеГит(
        ["cat-file", "blob", объектФинальногоДопуска], корень: корень
      )
    )
    let очередь = try КодированиеВозобновляемойЦепочки.объект(
      ИнструментыВозобновляемойЦепочки.данныеГит(
        ["cat-file", "blob", объектФинальнойОчереди], корень: корень
      )
    )
    let завершение = try объект(очередь, "last_completion")
    let ожидающие = try массивОбъектов(очередь, "waiting")
    let рабочаяКопияОчереди = try строка(очередь, "worktree_id")
    let рабочаяСсылкаОчереди = try строка(очередь, "branch_ref")
    let задачаДопуска = try строка(допуск, "идентификатор_задачи")
    let поколениеДопуска = try строка(допуск, "поколение")
    let базаДопуска = try строка(допуск, "базовая_вершина")
    let видЗавершения = try строка(завершение, "kind")
    let задачаЗавершения = try строка(завершение, "task_id")
    let поколениеЗавершения = try строка(завершение, "generation")
    let вершинаЗавершения = try строка(завершение, "head")
    return очередь["owner"] is NSNull
      && ожидающие.isEmpty
      && рабочаяКопияОчереди == рабочаяКопия
      && рабочаяСсылкаОчереди == рабочаяСсылка
      && задачаДопуска == "задача-цепочки-03"
      && поколениеДопуска == поколениеЗавершения
      && базаДопуска == вершина
      && видЗавершения == "finished_clean"
      && задачаЗавершения == "задача-цепочки-03"
      && вершинаЗавершения == вершина
  }

  private static func проверитьСамохэш(
    _ объект: [String: Any],
    поле: String
  ) throws -> Bool {
    var безХэша = объект
    guard let ожидаемый = безХэша.removeValue(forKey: поле) as? String else { return false }
    return хэш(try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(безХэша)) == ожидаемый
  }

  private static func путьСоответствует(_ путь: String, шаблону шаблон: String) -> Bool {
    if шаблон.hasSuffix("/**") {
      return путь.hasPrefix(String(шаблон.dropLast(3)) + "/")
    }
    return путь == шаблон
  }
}

private func данныеИзТекущейВершины(_ путь: String, корень: URL) throws -> Data {
  try ИнструментыВозобновляемойЦепочки.данныеГит(
    ["show", "HEAD:\(путь)"], корень: корень
  )
}

private func хэш(_ данные: Data) -> String {
  "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}

private func добавитьХэш(
  _ исходный: [String: Any],
  поле: String
) throws -> [String: Any] {
  var результат = исходный
  результат.removeValue(forKey: поле)
  результат[поле] = хэш(
    try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(результат)
  )
  return результат
}

private func объект(_ корень: [String: Any], _ поле: String) throws -> [String: Any] {
  guard let значение = корень[поле] as? [String: Any] else {
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неверныйОтвет(
      "Поле \(поле) не является объектом."
    )
  }
  return значение
}

private func массивОбъектов(
  _ корень: [String: Any],
  _ поле: String
) throws -> [[String: Any]] {
  guard let значение = корень[поле] as? [[String: Any]] else {
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неверныйОтвет(
      "Поле \(поле) не является массивом объектов."
    )
  }
  return значение
}

private func строки(_ текст: String) throws -> [String] {
  текст.split(separator: "\n").map(String.init)
}

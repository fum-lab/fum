  private static func ожидатьРезультатСессии(
    в управление: URL,
    задача: String
  ) throws -> РезультатСессииВозобновляемойЦепочки {
    let адрес = адресРезультатаСессии(управление, задача: задача)
    let адресОшибки = адресОшибкиСессии(управление, задача: задача)
    let крайнийСрок = Date().addingTimeInterval(120)
    while Date() < крайнийСрок {
      if FileManager.default.fileExists(atPath: адрес.path) {
        return try JSONDecoder().decode(
          РезультатСессииВозобновляемойЦепочки.self,
          from: WritingSubnodePersistence.readStableRegularFile(
            at: адрес, maximumBytes: 256 * 1_024
          )
        )
      }
      if FileManager.default.fileExists(atPath: адресОшибки.path) {
        let данные = try WritingSubnodePersistence.readStableRegularFile(
          at: адресОшибки, maximumBytes: 256 * 1_024
        )
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Сессия \(задача) завершилась ошибкой: \(String(decoding: данные, as: UTF8.self))"
        )
      }
      Thread.sleep(forTimeInterval: 0.02)
    }
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
      "Сессия \(задача) не опубликовала результат за 120 секунд."
    )
  }

  private static func ожидатьОшибкуСессии(
    в управление: URL,

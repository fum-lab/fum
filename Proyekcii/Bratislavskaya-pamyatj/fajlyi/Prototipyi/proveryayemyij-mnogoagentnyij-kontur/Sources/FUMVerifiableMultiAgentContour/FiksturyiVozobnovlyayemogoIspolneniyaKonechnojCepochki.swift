  private static func собратьИтоговыйОтчёт(
    корень: URL,
    управление: URL,
    назначение: ПодготовленноеНазначениеВозобновляемойЦепочки,
    проверкаИсполнителя: ОтчётПроверкиУниверсальногоФоркИсполнителя,
    сессии: [РезультатСессииВозобновляемойЦепочки],
    общаяДиректорияДо: String,
    общаяДиректорияПосле: String,
    целеваяВершинаДо: String,
    целеваяВершинаПосле: String,
    финальныйПовторИдемпотентен: Bool
  ) throws -> ОтчётВозобновляемогоИсполненияКонечнойЦепочки {
    guard let ссылкаПакета = сессии[2].ссылкаПакетаПередачи,
      let объектПакета = сессии[2].объектПакетаПередачи
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Финальная сессия не материализовала пакет передачи после finish-clean."
      )
    }
    let данныеПакета = try ИнструментыВозобновляемойЦепочки.данныеГит(
      ["cat-file", "blob", объектПакета], корень: корень
    )
    let пакет = try КодированиеВозобновляемойЦепочки.объект(данныеПакета)
    let проверен = try ПроверкаПакетаПередачиВозобновляемойЦепочки.проверить(
      данныеПакета,
      кореньЧекаута: корень,
      кореньУправления: управление,
      ожидаемаяСсылка: ссылкаПакета
    )
    var подменаВершины = пакет
    подменаВершины["готовая_вершина"] = назначение.база
    var подменаБюджета = пакет
    var остатокПодмены = try объект(пакет, "остаток_бюджета")
    остатокПодмены["токены"] = 799
    подменаБюджета["остаток_бюджета"] = остатокПодмены
    var подменаОбласти = пакет
    подменаОбласти["пути_совокупного_изменения"] = ["Планирование/секреты/подмена"]
    var подменаПринятия = пакет
    подменаПринятия["результат_принят"] = true
    let простыеПодменыОтклонены = try [
      подменаВершины,
      подменаБюджета,
      подменаОбласти,
      подменаПринятия,
    ].allSatisfy { подмена in
      try проверитьПодменуПакетаСУказателем(
        подмена,
        исходныйОбъект: объектПакета,
        ссылка: ссылкаПакета,
        корень: корень,
        управление: управление
      )
    }
    let самосогласованнаяПодменаКорнейОтклонена = try проверитьСамосогласованнуюПодменуКорней(
      исходныйПакет: пакет,
      исходныйОбъектПакета: объектПакета,
      ссылкаПакета: ссылкаПакета,
      корень: корень,
      управление: управление
    )
    let коммиты = try строки(
      ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-list", "--reverse", "\(назначение.база)..HEAD"],
        корень: корень
      )
    )
    let коммитыПакета = пакет["коммиты"] as? [String] ?? []
    let пути = пакет["пути_совокупного_изменения"] as? [String] ?? []
    let внешние = пакет["внешние_задачи"] as? [String] ?? []
    let квитанции = try строки(
      ИнструментыВозобновляемойЦепочки.текстГит(
        [
          "for-each-ref", "--format=%(refname)",
          "refs/fum/квитанции-связанных-коммитов/",
        ],
        корень: корень
      )
    )
    let временные = try ИнструментыВозобновляемойЦепочки.текстГит(
      [
        "for-each-ref", "--format=%(refname)",
        "refs/heads/fum-step/", "refs/fum/results/",
      ],
      корень: корень
    ).isEmpty
    let линейный = try коммиты.enumerated().allSatisfy { индекс, коммит in
      let родители =
        try строки(
          ИнструментыВозобновляемойЦепочки.текстГит(
            ["rev-list", "--parents", "-n", "1", коммит], корень: корень
          )
        ).first?.split(separator: " ").map(String.init) ?? []
      let ожидаемыйРодитель = индекс == 0 ? назначение.база : коммиты[индекс - 1]
      return родители == [коммит, ожидаемыйРодитель]
    }
    guard let объектФинальнойОчереди = сессии[2].объектОчереди else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Finish-clean не вернул объект очереди."
      )
    }
    let финальнаяОчередь = try КодированиеВозобновляемойЦепочки.объект(
      ИнструментыВозобновляемойЦепочки.данныеГит(
        ["cat-file", "blob", объектФинальнойОчереди], корень: корень
      )
    )
    let завершение = финальнаяОчередь["last_completion"] as? [String: Any]
    let чисто =
      завершение?["kind"] as? String == "finished_clean"
      && завершение?["task_id"] as? String == "задача-цепочки-03"
      && завершение?["head"] as? String == сессии[1].новаяВершина
    let числоНачальных = try числоСозданий(в: управление, вид: "начальная")
    let числоПродолжений = try числоСозданий(в: управление, вид: "продолжение")
    let однаРабочаяКопия =
      общаяДиректорияДо == общаяДиректорияПосле
      && Set(сессии.map(\.идентификаторРабочейКопии)) == [назначение.рабочаяКопия]
    let происхождениеСессий = try проверитьПроисхождениеСессий(
      сессии,
      управление: управление,
      назначение: назначение
    )
    let проверкаДелегирования = сессии[2].проверкаДелегирования ?? "отсутствует"
    let всеКритерии =
      проверкаИсполнителя.решение == .допустимо
      && проверкаДелегирования == "допустимо"
      && коммиты.count == 2
      && коммиты == коммитыПакета
      && сессии.map(\.исход) == ["committed", "committed", "finished_clean"]
      && сессии.map(\.состояниеСелектора) == ["ready", "ready", "not_ready"]
      && Set(сессии.map(\.идентификаторЗадачи)).count == 3
      && Set(сессии.map(\.идентификаторПроцесса)).count == 3
      && происхождениеСессий
      && числоНачальных == 1
      && числоПродолжений == 2
      && квитанции.count == 2
      && чисто
      && финальныйПовторИдемпотентен
      && целеваяВершинаДо == целеваяВершинаПосле
      && однаРабочаяКопия
      && линейный
      && временные
      && проверен
      && простыеПодменыОтклонены
      && самосогласованнаяПодменаКорнейОтклонена
      && внешние.count == 2
      && Set(внешние).isDisjoint(with: Set(сессии.map(\.идентификаторЗадачи)))
      && (пакет["создан_pull_request"] as? Bool) == false
      && (пакет["результат_принят"] as? Bool) == false
    return ОтчётВозобновляемогоИсполненияКонечнойЦепочки(
      решение: всеКритерии ? "принято" : "отклонено",
      проверкаУниверсальногоИсполнителя: String(describing: проверкаИсполнителя.решение),
      проверкаДелегирования: проверкаДелегирования,
      исходнаяВершина: назначение.база,
      готоваяВершина: сессии[1].новаяВершина,
      коммиты: коммиты,
      коммитыПакета: коммитыПакета,
      задачиЦепочки: сессии.map(\.идентификаторЗадачи),
      процессыСессий: сессии.map(\.идентификаторПроцесса),
      состоянияСелектора: сессии.map(\.состояниеСелектора),
      числоСозданийНачальнойЗадачи: числоНачальных,
      числоСозданийПродолжений: числоПродолжений,
      числоСвязанныхКвитанций: квитанции.count,
      финальноеЧистоеЗавершение: чисто,
      финальныйПовторИдемпотентен: финальныйПовторИдемпотентен,
      идентификаторРабочейКопии: назначение.рабочаяКопия,
      рабочаяСсылка: назначение.рабочаяСсылка,
      целеваяСсылка: "refs/heads/master",
      целеваяВершинаДо: целеваяВершинаДо,
      целеваяВершинаПосле: целеваяВершинаПосле,
      однаФизическаяРабочаяКопия: однаРабочаяКопия,
      диапазонОднородительский: линейный,
      временныеСсылкиОтсутствуют: временные,
      пакетПередачиПроверен: проверен,
      подменаПакетаОтклонена: простыеПодменыОтклонены,
      самосогласованнаяПодменаКорнейОтклонена: самосогласованнаяПодменаКорнейОтклонена,
      путиСовокупногоИзменения: пути,
      хэшСовокупногоИзменения: try строка(пакет, "хэш_совокупного_изменения"),
      внешниеЗадачи: внешние,
      созданЗапросНаСлияние: пакет["создан_pull_request"] as? Bool ?? true,
      результатПринят: пакет["результат_принят"] as? Bool ?? true
    )
  }

  private static func проверитьПодменуПакетаСУказателем(
    _ подмена: [String: Any],
    исходныйОбъект: String,
    ссылка: String,
    корень: URL,
    управление: URL
  ) throws -> Bool {
    let данные = try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(подмена)
    let объектПодмены = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["hash-object", "-w", "--stdin"], корень: корень, ввод: данные
    )
    _ = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["update-ref", ссылка, объектПодмены, исходныйОбъект], корень: корень
    )
    do {
      let отклонено = try !ПроверкаПакетаПередачиВозобновляемойЦепочки.проверить(
        данные,
        кореньЧекаута: корень,
        кореньУправления: управление,
        ожидаемаяСсылка: ссылка
      )
      _ = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["update-ref", ссылка, исходныйОбъект, объектПодмены], корень: корень
      )
      return отклонено
    } catch {
      _ = try? ИнструментыВозобновляемойЦепочки.текстГит(
        ["update-ref", ссылка, исходныйОбъект, объектПодмены], корень: корень
      )
      throw error
    }
  }

  private static func проверитьСамосогласованнуюПодменуКорней(

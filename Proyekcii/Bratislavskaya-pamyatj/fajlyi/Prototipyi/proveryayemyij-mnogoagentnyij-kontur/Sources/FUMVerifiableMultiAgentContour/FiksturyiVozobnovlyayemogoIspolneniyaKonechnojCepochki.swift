  ) throws -> [String: Any] {
    let адрес = адресОшибкиСессии(управление, задача: задача)
    let крайнийСрок = Date().addingTimeInterval(120)
    while Date() < крайнийСрок {
      if FileManager.default.fileExists(atPath: адрес.path) {
        return try КодированиеВозобновляемойЦепочки.объект(
          WritingSubnodePersistence.readStableRegularFile(
            at: адрес,
            maximumBytes: 256 * 1_024
          )
        )
      }
      if FileManager.default.fileExists(
        atPath: адресРезультатаСессии(управление, задача: задача).path
      ) {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Сессия \(задача) опубликовала успех вместо ожидаемого отказа."
        )
      }
      Thread.sleep(forTimeInterval: 0.02)
    }
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
      "Сессия \(задача) не опубликовала ожидаемую ошибку за 120 секунд."
    )
  }

  private static func дождатьсяДочернихСессий(в управление: URL) throws {
    let вторая = try ожидатьРезультатСессии(
      в: управление,
      задача: "задача-цепочки-02"
    )
    let финальная = try ожидатьРезультатСессии(
      в: управление,
      задача: "задача-цепочки-03"
    )
    guard вторая.идентификаторЗадачи == "задача-цепочки-02",
      вторая.исход == "committed",
      финальная.идентификаторЗадачи == "задача-цепочки-03",
      финальная.исход == "finished_clean"
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Дочерние persistent-сессии не завершили commit и finish-clean."
      )
    }
    try дождатьсяЗавершенияПроцесса(
      вторая.идентификаторПроцесса,
      задача: вторая.идентификаторЗадачи
    )
    try дождатьсяЗавершенияПроцесса(
      финальная.идентификаторПроцесса,
      задача: финальная.идентификаторЗадачи
    )
  }

  private static func дождатьсяЗавершенияПроцесса(
    _ идентификаторПроцесса: Int32,
    задача: String
  ) throws {
    let крайнийСрок = Date().addingTimeInterval(10)
    while Date() < крайнийСрок {
      if Darwin.kill(идентификаторПроцесса, 0) != 0 {
        guard errno == ESRCH else {
          throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
            "Не удалось проверить завершение процесса сессии \(задача)."
          )
        }
        return
      }
      Thread.sleep(forTimeInterval: 0.02)
    }
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
      "Процесс сессии \(задача) не завершился за 10 секунд."
    )
  }


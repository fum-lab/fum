    let объектСостояния = try записатьИлиСверитьСсылку(
      данныеСостояния,
      ссылка: ссылкаСостояния,
      корень: кореньЧекаута
    )
    guard
      try создатьВнешниеЗадачиПослеГотовности(
        в: кореньУправления,
        объектСостояния: объектСостояния,
        хэшСостояния: try строка(состояние, "хэш_состояния"),
        готоваяВершина: вершина
      ) == внешние
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "После закрепления готового состояния созданы другие внешние задачи."
      )
    }

    let коммиты = try строки(
      ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-list", "--reverse", "\(база)..\(вершина)"],
        корень: кореньЧекаута
      )
    )
    let данныеИзменения = try ИнструментыВозобновляемойЦепочки.данныеГит(

public enum ФикстурыВозобновляемогоИсполненияКонечнойЦепочки {
  public static func выполнитьДвухшаговую(
    исполняемыйФайлПробника: URL
  ) throws -> ОтчётВозобновляемогоИсполненияКонечнойЦепочки {
    try ФикстурыУниверсальногоФоркИсполнителя.сФикстурой(
      имя: "валидная-цепочка"
    ) { фикстура in
      let проверкаИсполнителя = ПроверкаУниверсальногоФоркИсполнителя.проверить(
        фикстура.регистрация,
        контекст: фикстура.контекст
      )
      guard проверкаИсполнителя.решение == .допустимо else {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Исходная топология универсального исполнителя недопустима: \(проверкаИсполнителя.нарушения)"
        )
      }
      let корень = фикстура.контекст.пишущийКлонИсполнителя
      let управление = корень.deletingLastPathComponent().appendingPathComponent(
        "управление-возобновляемой-цепочкой",
        isDirectory: true
      )
      try WritingSubnodePersistence.ensurePlainDirectory(управление)
      try записатьСозданиеНачальнойЗадачи(в: управление)
      let назначение =
        try СборкаЖивогоДиапазонаВозобновляемойЦепочки
        .подготовитьНазначение(
          кореньЧекаута: корень,
          регистрацияИсполнителя: фикстура.регистрация
        )
      let общаяДиректорияДо = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-parse", "--path-format=absolute", "--git-common-dir"],
        корень: корень
      )
      let целеваяВершинаДо = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-parse", "refs/heads/master"], корень: корень
      )

      let первая = try запуститьСессию(
        корень: корень,
        управление: управление,
        задача: "задача-цепочки-01",
        пробник: исполняемыйФайлПробника,
        режим: .обычный
      )
      let вторая = try ожидатьРезультатСессии(
        в: управление, задача: "задача-цепочки-02"
      )
      let финальная = try ожидатьРезультатСессии(
        в: управление, задача: "задача-цепочки-03"
      )
      guard первая.исход == "committed", вторая.исход == "committed",
        финальная.исход == "finished_clean"
      else {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Положительный сценарий не завершил два commit и finish-clean."
        )
      }
      try FileManager.default.removeItem(
        at: адресРезультатаСессии(управление, задача: "задача-цепочки-03")
      )
      let повторФинала = try запуститьПовторПродолжения(
        корень: корень,
        управление: управление,
        задача: "задача-цепочки-03",
        пробник: исполняемыйФайлПробника
      )
      let финальныйПовторИдемпотентен =
        повторФинала.исход == "finished_clean"
        && повторФинала.новаяВершина == финальная.новаяВершина
        && повторФинала.объектОчереди == финальная.объектОчереди
        && повторФинала.объектПакетаПередачи == финальная.объектПакетаПередачи
        && повторФинала.идентификаторПродолжения == nil
      let целеваяВершинаПосле = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-parse", "refs/heads/master"], корень: корень
      )
      let общаяДиректорияПосле = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-parse", "--path-format=absolute", "--git-common-dir"],
        корень: корень
      )
      return try собратьИтоговыйОтчёт(
        корень: корень,
        управление: управление,
        назначение: назначение,
        проверкаИсполнителя: проверкаИсполнителя,
        сессии: [первая, вторая, финальная],
        общаяДиректорияДо: общаяДиректорияДо,
        общаяДиректорияПосле: общаяДиректорияПосле,
        целеваяВершинаДо: целеваяВершинаДо,
        целеваяВершинаПосле: целеваяВершинаПосле,
        финальныйПовторИдемпотентен: финальныйПовторИдемпотентен
      )
    }
  }

  public static func проверитьГраницыСбоев(
    исполняемыйФайлПробника: URL
  ) throws -> ОтчётГраницСбоевВозобновляемойЦепочки {
    let неоднозначность = try проверитьНеоднозначноеСоздание(
      исполняемыйФайлПробника: исполняемыйФайлПробника
    )
    let потеря = try проверитьПотерянныйОтвет(
      исполняемыйФайлПробника: исполняемыйФайлПробника
    )
    let остановка = try проверитьОстановкуПослеПодтверждения(
      исполняемыйФайлПробника: исполняемыйФайлПробника
    )
    let подменаДерева = try проверитьПодменуПодготовленногоДерева(
      исполняемыйФайлПробника: исполняемыйФайлПробника
    )
    let токены = try проверитьОтказГраницы(
      исполняемыйФайлПробника: исполняемыйФайлПробника,
      бюджеты: (1_199, 60, 20),
      режим: .обычный
    )
    let секунды = try проверитьОтказГраницы(
      исполняемыйФайлПробника: исполняемыйФайлПробника,
      бюджеты: (2_000, 21, 20),
      режим: .обычный
    )
    let файлы = try проверитьОтказГраницы(
      исполняемыйФайлПробника: исполняемыйФайлПробника,
      бюджеты: (2_000, 60, 13),
      режим: .обычный
    )
    let незаявленный = try проверитьОтказГраницы(
      исполняемыйФайлПробника: исполняемыйФайлПробника,
      режим: .незаявленныйПуть
    )
    let внеОбласти = try проверитьОтказГраницы(
      исполняемыйФайлПробника: исполняемыйФайлПробника,
      режим: .заявленныйПутьВнеОбласти
    )
    let проверка = try проверитьОтказГраницы(
      исполняемыйФайлПробника: исполняемыйФайлПробника,
      режим: .неуспешнаяПроверка
    )
    return ОтчётГраницСбоевВозобновляемойЦепочки(
      неоднозначностьЗаблокировалаКоммит: неоднозначность.заблокирован,
      неоднозначностьНеПовторилаСоздание: неоднозначность.созданий == 1,
      вершинаПриНеоднозначностиНеИзменилась: неоднозначность.вершинаНеИзменилась,
      потерянныйОтветВосстановленПоКвитанции: потеря.восстановлен,
      потерянныйОтветНеПовторилСоздание: потеря.созданийПервойЗадачей == 1,
      точныйПовторНеСоздалВторойКоммит: потеря.коммитовПервойЗадачи == 1,
      изменённыйПовторОтклонён: потеря.конфликт,
      остановкаПослеПодтвержденияВосстановлена: остановка.восстановлен,
      остановкаНеПовторилаСоздание: остановка.созданийПервойЗадачей == 1,
      вершинаПриОстановкеНеИзменилась: остановка.вершинаНеИзменилась,
      подменённоеДеревоОтклонено: подменаДерева.отклонено,
      подменаДереваНеПродвинулаВетку: подменаДерева.вершинаНеИзменилась,
      подменаДереваНеПовторилаСоздание: подменаДерева.созданийПервойЗадачей == 1,
      подменаДереваПослеИсправленияВосстановлена: подменаДерева.восстановлен,
      превышениеТокеновОтклонено: токены,
      превышениеСекундОтклонено: секунды,
      превышениеИзменённыхФайловОтклонено: файлы,
      незаявленныйПутьОтклонён: незаявленный,
      заявленныйПутьВнеОбластиОтклонён: внеОбласти,
      неуспешнаяПроверкаОтклонена: проверка
    )
  }

  private static func проверитьОтказГраницы(
    исполняемыйФайлПробника: URL,
    бюджеты: (Int, Int, Int)? = nil,
    режим: РежимСессииВозобновляемойЦепочки
  ) throws -> Bool {
    try ФикстурыУниверсальногоФоркИсполнителя.сФикстурой(
      имя: "валидная-цепочка"
    ) { фикстура in
      let корень = фикстура.контекст.пишущийКлонИсполнителя
      let управление = корень.deletingLastPathComponent().appendingPathComponent(
        "управление-отказом-границы-\(режим.rawValue)", isDirectory: true
      )
      try WritingSubnodePersistence.ensurePlainDirectory(управление)
      try записатьСозданиеНачальнойЗадачи(в: управление)
      let назначение =
        try СборкаЖивогоДиапазонаВозобновляемойЦепочки
        .подготовитьНазначение(
          кореньЧекаута: корень,
          регистрацияИсполнителя: фикстура.регистрация,
          бюджеты: бюджеты
        )
      if бюджеты != nil {
        let первая = try запуститьСессию(
          корень: корень,
          управление: управление,
          задача: "задача-цепочки-01",
          пробник: исполняемыйФайлПробника,
          режим: .обычный
        )
        guard первая.исход == "committed" else { return false }
        let ошибка = try ожидатьОшибкуСессии(
          в: управление,
          задача: "задача-цепочки-02"
        )
        let процесс = Int32(try целое(ошибка, "идентификатор_процесса"))
        try дождатьсяЗавершенияПроцесса(процесс, задача: "задача-цепочки-02")
        let вершина = try ИнструментыВозобновляемойЦепочки.текстГит(
          ["rev-parse", "HEAD"], корень: корень
        )
        let квитанции = try строки(
          ИнструментыВозобновляемойЦепочки.текстГит(
            [
              "for-each-ref", "--format=%(refname)",
              "refs/fum/квитанции-связанных-коммитов/",
            ],
            корень: корень
          )
        )
        let созданияПродолжений = try числоСозданий(
          в: управление,
          вид: "продолжение"
        )
        return вершина == первая.новаяВершина
          && вершина != назначение.база
          && (ошибка["описание"] as? String)?.contains("Остаток бюджета") == true
          && созданияПродолжений == 1
          && квитанции.count == 1
      }
      let отказ = try запуститьСессиюОжидаяОтказ(
        корень: корень,
        управление: управление,
        задача: "задача-цепочки-01",
        пробник: исполняемыйФайлПробника,
        режим: режим
      )
      let вершина = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-parse", "HEAD"], корень: корень
      )
      let квитанции = try ИнструментыВозобновляемойЦепочки.текстГит(
        [
          "for-each-ref", "--format=%(refname)",
          "refs/fum/квитанции-связанных-коммитов/",
        ],
        корень: корень
      )
      let ожидаемыйФрагмент: String
      switch режим {
      case .незаявленныйПуть, .заявленныйПутьВнеОбласти:
        ожидаемыйФрагмент = "Фактический staged diff"
      case .неуспешнаяПроверка:
        ожидаемыйФрагмент = "Фактический результат не прошёл"
      default:
        ожидаемыйФрагмент = ""
      }
      let созданияПродолжений = try числоСозданий(
        в: управление,
        вид: "продолжение"
      )
      return отказ.код == 3
        && !ожидаемыйФрагмент.isEmpty
        && отказ.текст.contains(ожидаемыйФрагмент)
        && вершина == назначение.база
        && созданияПродолжений == 0
        && квитанции.isEmpty
    }
  }

  private static func проверитьНеоднозначноеСоздание(
    исполняемыйФайлПробника: URL
  ) throws -> (заблокирован: Bool, созданий: Int, вершинаНеИзменилась: Bool) {
    try ФикстурыУниверсальногоФоркИсполнителя.сФикстурой(
      имя: "валидная-цепочка"
    ) { фикстура in
      let корень = фикстура.контекст.пишущийКлонИсполнителя
      let управление = корень.deletingLastPathComponent().appendingPathComponent(
        "управление-неоднозначностью",
        isDirectory: true
      )
      try WritingSubnodePersistence.ensurePlainDirectory(управление)
      try записатьСозданиеНачальнойЗадачи(в: управление)
      _ = try СборкаЖивогоДиапазонаВозобновляемойЦепочки.подготовитьНазначение(
        кореньЧекаута: корень,
        регистрацияИсполнителя: фикстура.регистрация
      )
      let вершинаДо = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-parse", "HEAD"], корень: корень
      )
      let первый = try запуститьСессию(
        корень: корень,
        управление: управление,
        задача: "задача-цепочки-01",
        пробник: исполняемыйФайлПробника,
        режим: .неоднозначноеСоздание
      )
      let второй = try запуститьСессию(
        корень: корень,
        управление: управление,
        задача: "задача-цепочки-01",
        пробник: исполняемыйФайлПробника,
        режим: .обычный
      )
      let вершинаПосле = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-parse", "HEAD"], корень: корень
      )
      return (
        первый.исход == "blocked" && второй.исход == "blocked",
        try числоСозданий(в: управление, вид: "продолжение"),
        вершинаДо == вершинаПосле
      )
    }
  }

  private static func проверитьПотерянныйОтвет(
    исполняемыйФайлПробника: URL
  ) throws -> (
    восстановлен: Bool,
    созданийПервойЗадачей: Int,
    коммитовПервойЗадачи: Int,
    конфликт: Bool
  ) {
    try ФикстурыУниверсальногоФоркИсполнителя.сФикстурой(
      имя: "валидная-цепочка"
    ) { фикстура in
      let корень = фикстура.контекст.пишущийКлонИсполнителя
      let управление = корень.deletingLastPathComponent().appendingPathComponent(
        "управление-потерянным-ответом",
        isDirectory: true
      )
      try WritingSubnodePersistence.ensurePlainDirectory(управление)
      try записатьСозданиеНачальнойЗадачи(в: управление)
      let назначение =
        try СборкаЖивогоДиапазонаВозобновляемойЦепочки
        .подготовитьНазначение(
          кореньЧекаута: корень,
          регистрацияИсполнителя: фикстура.регистрация
        )
      let потерянный = try запуститьСессию(
        корень: корень,
        управление: управление,
        задача: "задача-цепочки-01",
        пробник: исполняемыйФайлПробника,
        режим: .потерятьОтветКоммита
      )
      let восстановленный = try запуститьСессию(
        корень: корень,
        управление: управление,
        задача: "задача-цепочки-01",
        пробник: исполняемыйФайлПробника,
        режим: .обычный
      )
      let конфликт = try запуститьСессию(
        корень: корень,
        управление: управление,
        задача: "задача-цепочки-01",
        пробник: исполняемыйФайлПробника,
        режим: .изменённыйПовтор
      )
      try дождатьсяДочернихСессий(в: управление)
      let коммитыПервойЗадачи = try строки(
        ИнструментыВозобновляемойЦепочки.текстГит(
          ["rev-list", "--reverse", "\(назначение.база)..\(потерянный.новаяВершина)"],
          корень: корень
        )
      )
      return (
        потерянный.исход == "commit_response_lost"
          && восстановленный.исход == "committed"
          && потерянный.новаяВершина == восстановленный.новаяВершина
          && потерянный.объектКвитанции == восстановленный.объектКвитанции,
        try числоСозданий(
          в: управление,
          вид: "продолжение",
          родитель: "задача-цепочки-01"
        ),
        коммитыПервойЗадачи.count,
        конфликт.исход == "conflict"
      )
    }
  }


  static func ссылкаДопуска(_ задача: String) -> String {
    "refs/fum/допуски-конечной-цепочки/\(компонент(задача))"
  }

  private static func компонент(_ строка: String) -> String {
    SHA256.hash(data: Data(строка.utf8)).map { String(format: "%02x", $0) }.joined()
  }

  private static func записатьИлиСверитьСсылку(
    _ данные: Data,
    ссылка: String,
    корень: URL
  ) throws -> String {
    let ожидаемыйОбъект = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["hash-object", "-w", "--stdin"], корень: корень, ввод: данные
    )
    let существующий = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["for-each-ref", "--format=%(objectname)", ссылка], корень: корень
    )
    if !существующий.isEmpty {
      guard существующий == ожидаемыйОбъект,
        try ИнструментыВозобновляемойЦепочки.данныеГит(
          ["cat-file", "blob", существующий], корень: корень
        ) == данные
      else {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.конфликтПовтора
      }
      return существующий
    }
    _ = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["update-ref", ссылка, ожидаемыйОбъект, ""], корень: корень
    )
    return ожидаемыйОбъект
  }
}


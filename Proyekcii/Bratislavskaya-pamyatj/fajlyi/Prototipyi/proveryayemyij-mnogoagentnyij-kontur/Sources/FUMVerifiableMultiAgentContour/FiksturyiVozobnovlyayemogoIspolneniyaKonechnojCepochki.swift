    подменноеСостояние["хэш_назначения"] = try строка(
      подменноеНазначение,
      "хэш_назначения"
    )
    var переходы = try массивОбъектов(подменноеСостояние, "переходы")
    переходы[0]["идентификатор_карточки"] = "FUM-STEP-9002"
    подменноеСостояние["переходы"] = переходы
    подменноеСостояние = try добавитьХэш(
      подменноеСостояние,
      поле: "хэш_состояния"
    )
    let подменныеДанныеСостояния =
      try КодированиеВозобновляемойЦепочки
      .каноническиеДанныеОбъекта(подменноеСостояние)
    let объектПодменногоСостояния = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["hash-object", "-w", "--stdin"], корень: корень, ввод: подменныеДанныеСостояния
    )

    var подменныйПакет = исходныйПакет
    подменныйПакет["объект_назначения"] = объектПодменногоНазначения
    подменныйПакет["хэш_назначения"] = try строка(
      подменноеНазначение,
      "хэш_назначения"
    )
    подменныйПакет["объект_состояния"] = объектПодменногоСостояния
    подменныйПакет["хэш_состояния"] = try строка(
      подменноеСостояние,
      "хэш_состояния"
    )
    let подменныеДанныеПакета =
      try КодированиеВозобновляемойЦепочки
      .каноническиеДанныеОбъекта(подменныйПакет)
    let объектПодменногоПакета = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["hash-object", "-w", "--stdin"], корень: корень, ввод: подменныеДанныеПакета
    )

    let внешниеАдреса = ["проверяющая", "интеграционная"].map {
      управление.appendingPathComponent("создания/внешняя-\($0).json")
    }
    let исходныеВнешниеДанные = try внешниеАдреса.map {
      try WritingSubnodePersistence.readStableRegularFile(at: $0, maximumBytes: 64 * 1_024)
    }
    let подменныеВнешниеДанные = try исходныеВнешниеДанные.map { данные -> Data in
      var запись = try КодированиеВозобновляемойЦепочки.объект(данные)
      запись["объект_состояния"] = объектПодменногоСостояния
      запись["хэш_состояния"] = try строка(подменноеСостояние, "хэш_состояния")
      return try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(запись)
    }
    let прямыеПереходы = [
      (ссылкаНазначения, объектПодменногоНазначения, объектНазначения),
      (ссылкаСостояния, объектПодменногоСостояния, объектСостояния),
      (ссылкаПакета, объектПодменногоПакета, исходныйОбъектПакета),
    ]
    let обратныеПереходы = прямыеПереходы.map { ($0.0, $0.2, $0.1) }
    do {
      for (адрес, данные) in zip(внешниеАдреса, подменныеВнешниеДанные) {
        try данные.write(to: адрес, options: .atomic)
      }
      try переместитьСсылкиТранзакцией(прямыеПереходы, корень: корень)
      let отклонено = try !ПроверкаПакетаПередачиВозобновляемойЦепочки.проверить(
        подменныеДанныеПакета,
        кореньЧекаута: корень,
        кореньУправления: управление,
        ожидаемаяСсылка: ссылкаПакета
      )
      try переместитьСсылкиТранзакцией(обратныеПереходы, корень: корень)
      for (адрес, данные) in zip(внешниеАдреса, исходныеВнешниеДанные) {
        try данные.write(to: адрес, options: .atomic)
      }
      return отклонено
    } catch {
      _ = try? переместитьСсылкиТранзакцией(обратныеПереходы, корень: корень)
      for (адрес, данные) in zip(внешниеАдреса, исходныеВнешниеДанные) {
        try? данные.write(to: адрес, options: .atomic)
      }
      throw error
    }
  }

  private static func переместитьСсылкиТранзакцией(
    _ переходы: [(String, String, String)],
    корень: URL
  ) throws {
    let команды =
      (["start"]
      + переходы.map {
        "update \($0.0) \($0.1) \($0.2)"
      } + ["prepare", "commit", ""]).joined(separator: "\n")
    _ = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["update-ref", "--stdin"],
      корень: корень,
      ввод: Data(команды.utf8)
    )
  }

  private static func проверитьПроисхождениеСессий(
    _ сессии: [РезультатСессииВозобновляемойЦепочки],
    управление: URL,
    назначение: ПодготовленноеНазначениеВозобновляемойЦепочки
  ) throws -> Bool {
    guard сессии.count == 3 else { return false }
    let каталогСозданий = управление.appendingPathComponent("создания", isDirectory: true)
    let адресаСозданий = try FileManager.default.contentsOfDirectory(
      at: каталогСозданий,
      includingPropertiesForKeys: [.isRegularFileKey],
      options: [.skipsHiddenFiles]
    )
    let создания = try адресаСозданий.map { адрес in
      try КодированиеВозобновляемойЦепочки.объект(
        WritingSubnodePersistence.readStableRegularFile(
          at: адрес,
          maximumBytes: 64 * 1_024
        )
      )
    }
    for индекс in 1..<3 {
      let текущая = сессии[индекс]
      let родитель = сессии[индекс - 1]
      let свидетельство = try КодированиеВозобновляемойЦепочки.объект(
        WritingSubnodePersistence.readStableRegularFile(
          at: адресСвидетельстваОжидания(
            управление,
            задача: текущая.идентификаторЗадачи
          ),
          maximumBytes: 128 * 1_024
        )
      )
      let совпавшиеСоздания = создания.filter {
        $0["вид"] as? String == "продолжение"
          && $0["родитель"] as? String == родитель.идентификаторЗадачи
          && $0["идентификатор"] as? String == текущая.идентификаторЗадачи
          && $0["исход"] as? String == "создана"
      }
      guard совпавшиеСоздания.count == 1,
        try строка(свидетельство, "state") == "waiting",
        try строка(свидетельство, "task_id") == текущая.идентификаторЗадачи,
        try целое(свидетельство, "идентификатор_процесса")
          == Int(текущая.идентификаторПроцесса),
        try строка(свидетельство, "worktree_id") == назначение.рабочаяКопия,
        try строка(свидетельство, "branch_ref") == назначение.рабочаяСсылка,
        try строка(свидетельство, "acknowledged_head") == родитель.стараяВершина
      else { return false }
    }
    return true
  }


  static func проверитьИсторическийДопускИДочернийБилет(
    допуск: [String: Any],
    попытка: [String: Any],
    корень: URL
  ) throws {
    let данныеДопуска = try ИнструментыВозобновляемойЦепочки.данныеГит(
      ["cat-file", "blob", try строка(допуск, "объект_очереди")], корень: корень
    )
    let снимокДопуска = try КодированиеВозобновляемойЦепочки.объект(данныеДопуска)
    let владелец = try объект(снимокДопуска, "owner")
    guard try строка(владелец, "task_id") == строка(допуск, "идентификатор_задачи"),
      try строка(владелец, "ticket_id") == строка(допуск, "идентификатор_билета"),
      try целое(владелец, "seq") == целое(допуск, "номер_билета"),
      try строка(владелец, "generation") == строка(допуск, "поколение")
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Admission witness не воспроизводится из исторического queue blob."
      )
    }
    let данныеОжидания = try ИнструментыВозобновляемойЦепочки.данныеГит(
      ["cat-file", "blob", try строка(попытка, "объект_очереди_подтверждения")],
      корень: корень
    )
    let снимокОжидания = try КодированиеВозобновляемойЦепочки.объект(данныеОжидания)
    let ожидающие = try массивОбъектов(снимокОжидания, "waiting")
    let совпадения = try ожидающие.filter {
      try строка($0, "task_id") == строка(попытка, "идентификатор_продолжения")
    }
    guard совпадения.count == 1,
      try строка(совпадения[0], "ticket_id")
        == строка(попытка, "идентификатор_билета_продолжения"),
      try целое(совпадения[0], "seq")
        == целое(попытка, "номер_билета_продолжения"),
      try строка(совпадения[0], "acknowledged_head")
        == строка(допуск, "базовая_вершина")
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Continuation witness не воспроизводится из исторического queue blob."
      )
    }
  }

  private static func проверитьСнимокОчередиПослеДиапазона(
    _ очередь: [String: Any],
    ожидаемоеПродолжение: String,
    вершина: String
  ) throws {
    let ожидающие = try массивОбъектов(очередь, "waiting")
    guard очередь["owner"] is NSNull,
      ожидающие.count == 1,
      try строка(ожидающие[0], "task_id") == ожидаемоеПродолжение,
      let завершение = очередь["last_completion"] as? [String: Any],
      try строка(завершение, "kind") == "committed",
      try строка(завершение, "head") == вершина
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Ready-снимок очереди не закрепляет финальное ожидающее продолжение."
      )
    }
  }

  private static func создатьВнешниеЗадачиПослеГотовности(
    в управление: URL,
    объектСостояния: String,
    хэшСостояния: String,
    готоваяВершина: String
  ) throws -> [String] {
    let каталог = управление.appendingPathComponent("создания", isDirectory: true)
    try WritingSubnodePersistence.ensurePlainDirectory(каталог)
    let задачи = [
      ("проверяющая", "задача-проверки-готового-диапазона"),
      ("интеграционная", "задача-интеграции-готового-диапазона"),
    ]
    for (вид, идентификатор) in задачи {
      let объект: [String: Any] = [
        "схема": "fum.создание-задачи-конечной-цепочки.1",
        "родитель": "готовый-диапазон",
        "вид": вид,
        "идентификатор": идентификатор,
        "исход": "создана",
        "объект_состояния": объектСостояния,
        "хэш_состояния": хэшСостояния,
        "готовая_вершина": готоваяВершина,
      ]
      let данные = try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(объект)
      let адрес = каталог.appendingPathComponent("внешняя-\(вид).json")
      if FileManager.default.fileExists(atPath: адрес.path) {
        guard
          try WritingSubnodePersistence.readStableRegularFile(
            at: адрес, maximumBytes: 64 * 1_024
          ) == данные
        else {
          throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.конфликтПовтора
        }
      } else {
        try WritingSubnodePersistence.persistExclusive(данные, at: адрес)
      }
    }
    return задачи.map(\.1)
  }


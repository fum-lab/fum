    let целеваяВершина = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["rev-parse", "refs/heads/master"], корень: кореньЧекаута
    )
    let квитанционныеСсылки = try попытки.map { try строка($0, "ссылка_квитанции") }
    let квитанционныеОбъекты = try попытки.map { try строка($0, "объект_квитанции") }

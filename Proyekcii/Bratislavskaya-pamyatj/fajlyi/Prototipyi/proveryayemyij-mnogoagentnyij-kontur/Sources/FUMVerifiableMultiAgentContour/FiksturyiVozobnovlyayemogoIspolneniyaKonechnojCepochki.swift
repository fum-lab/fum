      return ПроверкаЗакрытойСхемы.проверитьДокумент(значение, по: схема)
    }
    guard нарушенияСхем.isEmpty else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Живые документы не прошли закрытые схемы: \(нарушенияСхем)"
      )
    }
    let отчёт = ПроверкаДелегированияКонечнойЦепочки.проверить(
      назначение: данныеНазначения,
      состояние: данныеСостояния,
      контекст: контекст
    )
    guard отчёт.решение == .допустимо else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Живой контекст не прошёл семантический валидатор: \(отчёт.нарушения)"

private func проверитьПаспортДерева(
  _ паспорт: [String: Any],
  контекст: КонтекстПроверкиДереваВетвевыхФорков,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) -> СведенияПаспортаДерева {
  let родитель = объектДерева(паспорт["родитель"]) ?? [:]
  let дети = массивОбъектовДерева(паспорт["дети"]) ?? []
  let модерация = объектДерева(паспорт["модерация"]) ?? [:]
  let идентификаторДерева = строкаДерева(паспорт["идентификатор_дерева"]) ?? ""
  let идентификаторПоколения =
    строкаДерева(паспорт["идентификатор_поколения"]) ?? ""
  let идентификаторРодителя = строкаДерева(родитель["идентификатор_fork"]) ?? ""
  let идентификаторыДетей = дети.compactMap {
    строкаДерева($0["идентификатор_fork"])
  }
  let родительскийРепозиторий =
    строкаДерева(родитель["идентификатор_репозитория"]) ?? ""
  let родительскаяСсылка = строкаДерева(родитель["рабочая_ссылка"]) ?? ""
  let ожидаемаяБаза = строкаДерева(родитель["исходная_вершина"]) ?? ""
  let хэшКритериев = строкаДерева(модерация["хэш_критериев"]) ?? ""

  if целоеДерева(паспорт["поколение_схемы"]) != 1 {
    добавитьНарушениеДерева(
      "неподдерживаемое_поколение_схемы",
      путь: "#/паспорт/поколение_схемы",
      сообщение: "Поддерживается только поколение схемы 1.",
      нарушения: &нарушения
    )
  }
  if дети.count != 2 {
    добавитьНарушениеДерева(
      "неверное_число_детей",
      путь: "#/паспорт/дети",
      сообщение: "Поколение должно содержать ровно двух детей.",
      нарушения: &нарушения
    )
  }

  let всеИдентификаторы = [идентификаторРодителя] + идентификаторыДетей
  if Set(всеИдентификаторы).count != всеИдентификаторы.count
    || всеИдентификаторы.contains("")
  {
    добавитьНарушениеДерева(
      "идентификаторы_fork_совпадают",
      путь: "#/паспорт/дети",
      сообщение: "Родитель и дети должны иметь разные устойчивые идентификаторы.",
      нарушения: &нарушения
    )
  }
  let стороны = дети.compactMap { строкаДерева($0["сторона"]) }
  if Set(стороны) != Set(["левая", "правая"]) || стороны.count != 2 {
    добавитьНарушениеДерева(
      "неверные_стороны_детей",
      путь: "#/паспорт/дети",
      сообщение: "Должны присутствовать ровно левая и правая стороны.",
      нарушения: &нарушения
    )
  }
  let дочерниеСсылки = дети.compactMap { строкаДерева($0["рабочая_ссылка"]) }
  if дочерниеСсылки.count != 2 || Set(дочерниеСсылки).count != 2 {
    добавитьНарушениеДерева(
      "дочерние_refs_совпадают",
      путь: "#/паспорт/дети",
      сообщение: "Дочерние полные рабочие refs должны различаться.",
      нарушения: &нарушения
    )
  }
  let дочерниеРабочиеКопии = дети.compactMap {
    строкаДерева($0["идентификатор_checkout"])
  }
  if дочерниеРабочиеКопии.count != 2
    || Set(дочерниеРабочиеКопии).count != 2
  {
    добавитьНарушениеДерева(
      "checkout_занят_другим_fork",
      путь: "#/паспорт/дети",
      сообщение: "Каждый ребёнок должен иметь отдельный живой checkout.",
      нарушения: &нарушения
    )
  }

  if строкаДерева(модерация["идентификатор_модератора"])
    != идентификаторРодителя
  {
    добавитьНарушениеДерева(
      "родитель_и_модератор_различаются",
      путь: "#/паспорт/модерация/идентификатор_модератора",
      сообщение: "Логическая идентичность модератора обязана совпадать с родителем.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(модерация["идентификатор_попытки"])?.isEmpty != false {
    добавитьНарушениеДерева(
      "попытка_модерации_отсутствует",
      путь: "#/паспорт/модерация/идентификатор_попытки",
      сообщение: "Попытка модерации должна иметь отдельную идентичность.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(модерация["идентификатор_репозитория"])
    != родительскийРепозиторий
    || строкаДерева(модерация["родительская_рабочая_ссылка"])
      != родительскаяСсылка
  {
    добавитьНарушениеДерева(
      "модерация_не_связана_с_родителем",
      путь: "#/паспорт/модерация",
      сообщение: "Модерация должна быть связана с парой репозитория и ref родителя.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(модерация["целевая_ссылка_интеграции"])
    != родительскаяСсылка
  {
    добавитьНарушениеДерева(
      "цель_интеграции_не_совпадает_с_родителем",
      путь: "#/паспорт/модерация/целевая_ссылка_интеграции",
      сообщение: "Цель первой версии обязана совпадать с рабочим ref родителя.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(модерация["ожидаемая_база"]) != ожидаемаяБаза {
    добавитьНарушениеДерева(
      "родительская_база_модерации_сдвинулась",
      путь: "#/паспорт/модерация/ожидаемая_база",
      сообщение: "Модерация должна замораживать исходную вершину родителя.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(модерация["ссылка_состояния"])
    == родительскаяСсылка
  {
    добавитьНарушениеДерева(
      "ссылка_состояния_модерации_не_отделена",
      путь: "#/паспорт/модерация/ссылка_состояния",
      сообщение: "Сага должна сохраняться в отдельном служебном ref.",
      нарушения: &нарушения
    )
  }

  let критерии = массивОбъектовДерева(модерация["критерии"]) ?? []
  if критерии.isEmpty
    || хэшПроизвольногоЗначенияДерева(критерии) != хэшКритериев
  {
    добавитьНарушениеДерева(
      "хэш_критериев_не_совпадает",
      путь: "#/паспорт/модерация/хэш_критериев",
      сообщение: "Хэш должен связывать весь упорядоченный набор критериев.",
      нарушения: &нарушения
    )
  }

  let формат = строкаДерева(паспорт["формат_git_объектов"]) ?? ""
  let ожидаемаяДлина = формат == "sha1" ? 40 : (формат == "sha256" ? 64 : 0)
  for (индекс, узел) in ([родитель] + дети).enumerated() {
    let вершина = строкаДерева(узел["исходная_вершина"]) ?? ""
    if вершина.count != ожидаемаяДлина
      || вершина.range(of: "^[0-9a-f]+$", options: .regularExpression) == nil
    {
      добавитьНарушениеДерева(
        "неверный_формат_oid",
        путь: "#/паспорт/узлы/\(индекс)/исходная_вершина",
        сообщение: "OID должен соответствовать общему формату объектов поколения.",
        нарушения: &нарушения
      )
    }
  }
  let исходное = объектДерева(паспорт["исходное_состояние"]) ?? [:]
  let доказательство = строкаДерева(исходное["хэш_доказательства"]) ?? ""
  let вершины = массивОбъектовДерева(исходное["вершины"]) ?? []
  let ожидаемыеПары = Set(
    ([родитель] + дети).map {
      (строкаДерева($0["идентификатор_fork"]) ?? "") + "\u{1F}"
        + (строкаДерева($0["идентификатор_репозитория"]) ?? "") + "\u{1F}"
        + (строкаДерева($0["исходная_вершина"]) ?? "")
    })
  let засвидетельствованныеПары = Set(
    вершины.map {
      (строкаДерева($0["идентификатор_fork"]) ?? "") + "\u{1F}"
        + (строкаДерева($0["идентификатор_репозитория"]) ?? "") + "\u{1F}"
        + (строкаДерева($0["oid"]) ?? "")
    })
  let доказанныеВершины = Set(
    вершины.map {
      ДоказаннаяВершинаИсходногоСостояния(
        идентификаторРазвилки: строкаДерева($0["идентификатор_fork"]) ?? "",
        идентификаторРепозитория: строкаДерева($0["идентификатор_репозитория"]) ?? "",
        вершина: строкаДерева($0["oid"]) ?? ""
      )
    })
  let доказаннаяЭквивалентность = ДоказаннаяЭквивалентностьИсходногоСостояния(
    форматОбъектов: формат,
    хэшДоказательства: доказательство,
    вершины: доказанныеВершины
  )
  if ожидаемыеПары != засвидетельствованныеПары
    || !контекст.доверенныеДоказательстваЭквивалентности.contains(
      доказаннаяЭквивалентность
    )
  {
    добавитьНарушениеДерева(
      "исходная_база_не_доказана",
      путь: "#/паспорт/исходное_состояние",
      сообщение: "Все репозитории должны иметь проверенные эквивалентные исходные вершины.",
      нарушения: &нарушения
    )
  }

  проверитьГраницыРекурсииДерева(
    родитель: родитель,
    дети: дети,
    границы: объектДерева(паспорт["границы"]) ?? [:],
    нарушения: &нарушения
  )
  let сохранённыеУзлы = массивОбъектовДерева(паспорт["сохранённые_узлы"]) ?? []
  let сохранённыеРазвилки =
    массивОбъектовДерева(паспорт["сохранённые_развилки"]) ?? []
  let числоКорней = проверитьСохранённоеДерево(
    узлы: сохранённыеУзлы,
    развилки: сохранённыеРазвилки,
    ожидаемыйКорень: строкаДерева(паспорт["идентификатор_корня"]) ?? "",
    нарушения: &нарушения
  )
  проверитьТекущееПоколениеВСохранённомДереве(
    родитель: родитель,
    дети: дети,
    идентификаторПоколения: идентификаторПоколения,
    сохранённыеУзлы: сохранённыеУзлы,
    сохранённыеРазвилки: сохранённыеРазвилки,
    нарушения: &нарушения
  )

  return СведенияПаспортаДерева(
    родитель: родитель,
    дети: дети,
    модерация: модерация,
    идентификаторДерева: идентификаторДерева,
    идентификаторПоколения: идентификаторПоколения,
    идентификаторРодителя: идентификаторРодителя,
    идентификаторыДетей: идентификаторыДетей,
    родительскийРепозиторий: родительскийРепозиторий,
    родительскаяСсылка: родительскаяСсылка,
    ожидаемаяБаза: ожидаемаяБаза,
    хэшКритериев: хэшКритериев,
    форматОбъектов: формат,
    числоКорней: числоКорней,
    числоУзлов: сохранённыеУзлы.count
  )
}

private func проверитьГраницыРекурсииДерева(
  родитель: [String: Any],
  дети: [[String: Any]],
  границы: [String: Any],
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  if целоеДерева(границы["коэффициент_ветвления"]) != 2
    || целоеДерева(границы["максимум_активных_детей"]) != 2
  {
    добавитьНарушениеДерева(
      "неверный_коэффициент_ветвления",
      путь: "#/паспорт/границы",
      сообщение: "Первая версия допускает коэффициент ветвления ровно 2.",
      нарушения: &нарушения
    )
  }
  if целоеДерева(границы["максимум_владельцев"]) != 1 {
    добавитьНарушениеДерева(
      "неверный_предел_владельцев",
      путь: "#/паспорт/границы/максимум_владельцев",
      сообщение: "У fork может быть не более одного владельца.",
      нарушения: &нарушения
    )
  }
  let остатокРодителя = целоеДерева(родитель["остаток_глубины"]) ?? -1
  let бюджетРодителя = объектДерева(родитель["бюджет"]) ?? [:]
  let полномочияРодителя = Set(массивСтрокДерева(родитель["полномочия"]) ?? [])
  let эффектыРодителя = Set(массивСтрокДерева(родитель["эффекты"]) ?? [])
  let заявленныйБюджет = объектДерева(границы["ресурсный_бюджет"]) ?? [:]
  let заявленныеПолномочия =
    Set(массивСтрокДерева(границы["разрешённые_полномочия"]) ?? [])
  let заявленныеЭффекты =
    Set(массивСтрокДерева(границы["разрешённые_эффекты"]) ?? [])
  if целоеДерева(границы["глубина_рекурсии"]) != остатокРодителя
    || !равныКаноническиеЗначенияДерева(заявленныйБюджет, бюджетРодителя)
    || заявленныеПолномочия != полномочияРодителя
    || заявленныеЭффекты != эффектыРодителя
  {
    добавитьНарушениеДерева(
      "границы_родителя_не_совпадают",
      путь: "#/паспорт/границы",
      сообщение:
        "Пределы поколения должны точно связывать глубину, бюджет, полномочия и эффекты родителя.",
      нарушения: &нарушения
    )
  }
  проверитьСужениеГраницДерева(
    родитель: родитель,
    дети: дети,
    путьДетей: "#/паспорт/дети",
    нарушения: &нарушения
  )
}

private func проверитьСужениеГраницДерева(
  родитель: [String: Any],
  дети: [[String: Any]],
  путьДетей: String,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  let остатокРодителя = целоеДерева(родитель["остаток_глубины"]) ?? -1
  let бюджетРодителя = объектДерева(родитель["бюджет"]) ?? [:]
  let полномочияРодителя = Set(массивСтрокДерева(родитель["полномочия"]) ?? [])
  let эффектыРодителя = Set(массивСтрокДерева(родитель["эффекты"]) ?? [])
  for (индекс, ребёнок) in дети.enumerated() {
    if (целоеДерева(ребёнок["остаток_глубины"]) ?? Int.max) >= остатокРодителя {
      добавитьНарушениеДерева(
        "остаток_глубины_не_уменьшен",
        путь: "\(путьДетей)/\(индекс)/остаток_глубины",
        сообщение: "Рекурсивный ребёнок обязан строго уменьшить конечный остаток глубины.",
        нарушения: &нарушения
      )
    }
    let бюджетРебёнка = объектДерева(ребёнок["бюджет"]) ?? [:]
    let расширенБюджет = ["токены", "секунды", "изменённые_файлы"].contains {
      (целоеДерева(бюджетРебёнка[$0]) ?? Int.max)
        > (целоеДерева(бюджетРодителя[$0]) ?? -1)
    }
    let полномочияРебёнка = Set(массивСтрокДерева(ребёнок["полномочия"]) ?? [])
    let эффектыРебёнка = Set(массивСтрокДерева(ребёнок["эффекты"]) ?? [])
    if расширенБюджет
      || !полномочияРебёнка.isSubset(of: полномочияРодителя)
      || !эффектыРебёнка.isSubset(of: эффектыРодителя)
    {
      добавитьНарушениеДерева(
        "ресурсные_границы_расширены",
        путь: "\(путьДетей)/\(индекс)",
        сообщение: "Потомок может только сужать ресурсы, полномочия и эффекты.",
        нарушения: &нарушения
      )
    }
  }
  let совокупныйБюджетРасширен = ["токены", "секунды", "изменённые_файлы"].contains {
    поле in
    let предел = целоеДерева(бюджетРодителя[поле]) ?? -1
    var сумма = 0
    for ребёнок in дети {
      let значение = целоеДерева((объектДерева(ребёнок["бюджет"]) ?? [:])[поле]) ?? Int.max
      let (новаяСумма, переполнение) = сумма.addingReportingOverflow(значение)
      сумма = переполнение ? Int.max : новаяСумма
    }
    return сумма > предел
  }
  if совокупныйБюджетРасширен {
    добавитьНарушениеДерева(
      "совокупный_ресурсный_бюджет_расширен",
      путь: путьДетей,
      сообщение: "Сумма ресурсов двух детей не должна превышать бюджет родителя.",
      нарушения: &нарушения
    )
  }
}

private func проверитьСохранённоеДерево(
  узлы: [[String: Any]],
  развилки: [[String: Any]],
  ожидаемыйКорень: String,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) -> Int {
  var узлыПоИдентификатору: [String: [String: Any]] = [:]
  var рабочиеПары: [String: String] = [:]
  var рабочиеКопии: [String: String] = [:]
  var корни: [String] = []
  for (индекс, узел) in узлы.enumerated() {
    let идентификатор = строкаДерева(узел["идентификатор_fork"]) ?? ""
    if let прежний = узлыПоИдентификатору[идентификатор],
      !равныКаноническиеЗначенияДерева(прежний, узел)
    {
      добавитьНарушениеДерева(
        "описание_fork_изменено",
        путь: "#/паспорт/сохранённые_узлы/\(индекс)",
        сообщение: "Неизменяемые поля одного fork расходятся между поколениями.",
        нарушения: &нарушения
      )
    } else {
      узлыПоИдентификатору[идентификатор] = узел
    }
    let репозиторий = строкаДерева(узел["идентификатор_репозитория"]) ?? ""
    let ссылка = строкаДерева(узел["рабочая_ссылка"]) ?? ""
    let пара = репозиторий + "\u{1F}" + ссылка
    if let владелец = рабочиеПары[пара], владелец != идентификатор {
      добавитьНарушениеДерева(
        "рабочая_пара_занята_другим_fork",
        путь: "#/паспорт/сохранённые_узлы/\(индекс)",
        сообщение: "Пара репозитория и полного ref навсегда принадлежит одному fork.",
        нарушения: &нарушения
      )
    } else {
      рабочиеПары[пара] = идентификатор
    }
    let идентификаторРабочейКопии =
      строкаДерева(узел["идентификатор_checkout"]) ?? ""
    if let владелец = рабочиеКопии[идентификаторРабочейКопии],
      владелец != идентификатор
    {
      добавитьНарушениеДерева(
        "checkout_занят_другим_fork",
        путь: "#/паспорт/сохранённые_узлы/\(индекс)",
        сообщение: "Один живой checkout не разделяется разными fork.",
        нарушения: &нарушения
      )
    } else {
      рабочиеКопии[идентификаторРабочейКопии] = идентификатор
    }
    if узел["идентификатор_родителя"] is NSNull
      || узел["идентификатор_родителя"] == nil
    {
      корни.append(идентификатор)
    }
  }
  if корни.count != 1 || корни.first != ожидаемыйКорень {
    добавитьНарушениеДерева(
      "второй_корень",
      путь: "#/паспорт/сохранённые_узлы",
      сообщение: "Сохраняемое дерево должно иметь ровно один заявленный корень.",
      нарушения: &нарушения
    )
  }

  var детиПоРодителю: [String: [String]] = [:]
  var родителиПоРебёнку: [String: [String]] = [:]
  for (индекс, развилка) in развилки.enumerated() {
    let родитель = строкаДерева(развилка["идентификатор_родителя"]) ?? ""
    let дети = массивСтрокДерева(развилка["дети"]) ?? []
    let концы = [родитель] + дети
    if концы.contains(where: { узлыПоИдентификатору[$0] == nil }) {
      добавитьНарушениеДерева(
        "неизвестный_узел_развилки",
        путь: "#/паспорт/сохранённые_развилки/\(индекс)",
        сообщение: "Каждый конец ребра порождения должен существовать в сохранённом дереве.",
        нарушения: &нарушения
      )
    }
    if дети.count != 2 || Set(дети).count != 2 {
      добавитьНарушениеДерева(
        "неверное_число_детей",
        путь: "#/паспорт/сохранённые_развилки/\(индекс)",
        сообщение: "Каждая состоявшаяся развилка содержит ровно двух разных детей.",
        нарушения: &нарушения
      )
    }
    if let дескрипторРодителя = узлыПоИдентификатору[родитель] {
      let дескрипторыДетей = дети.compactMap { узлыПоИдентификатору[$0] }
      if дескрипторыДетей.count == 2 {
        проверитьСужениеГраницДерева(
          родитель: дескрипторРодителя,
          дети: дескрипторыДетей,
          путьДетей: "#/паспорт/сохранённые_развилки/\(индекс)/дети",
          нарушения: &нарушения
        )
      }
    }
    if детиПоРодителю[родитель] != nil {
      добавитьНарушениеДерева(
        "повторная_развилка",
        путь: "#/паспорт/сохранённые_развилки/\(индекс)",
        сообщение: "Один узел может реализовать не более одной развилки.",
        нарушения: &нарушения
      )
    } else {
      детиПоРодителю[родитель] = дети
    }
    for ребёнок in дети {
      родителиПоРебёнку[ребёнок, default: []].append(родитель)
    }
  }
  for (ребёнок, родители) in родителиПоРебёнку where Set(родители).count > 1 {
    добавитьНарушениеДерева(
      "общий_ребёнок",
      путь: "#/паспорт/сохранённые_узлы/\(ребёнок)",
      сообщение: "Один ребёнок не может принадлежать двум родителям.",
      нарушения: &нарушения
    )
    добавитьНарушениеДерева(
      "лишний_родитель",
      путь: "#/паспорт/сохранённые_узлы/\(ребёнок)",
      сообщение: "Каждый некорневой узел должен иметь ровно одного родителя.",
      нарушения: &нарушения
    )
  }
  for узел in узлы {
    let идентификатор = строкаДерева(узел["идентификатор_fork"]) ?? ""
    guard идентификатор != ожидаемыйКорень else { continue }
    let заявленный = строкаДерева(узел["идентификатор_родителя"])
    let фактические = Set(родителиПоРебёнку[идентификатор] ?? [])
    if заявленный == nil || фактические.count != 1 || !фактические.contains(заявленный ?? "") {
      добавитьНарушениеДерева(
        "лишний_родитель",
        путь: "#/паспорт/сохранённые_узлы/\(идентификатор)",
        сообщение: "Родитель узла должен быть единственным и совпадать с ребром порождения.",
        нарушения: &нарушения
      )
    }
  }

  var цвета: [String: Int] = [:]
  var найденЦикл = false
  func посетить(_ узел: String) {
    if цвета[узел] == 1 {
      найденЦикл = true
      return
    }
    if цвета[узел] == 2 { return }
    цвета[узел] = 1
    for ребёнок in детиПоРодителю[узел] ?? [] {
      посетить(ребёнок)
    }
    цвета[узел] = 2
  }
  for идентификатор in узлыПоИдентификатору.keys {
    посетить(идентификатор)
  }
  if найденЦикл {
    добавитьНарушениеДерева(
      "цикл_происхождения",
      путь: "#/паспорт/сохранённые_развилки",
      сообщение: "Неизменяемые рёбра происхождения не должны образовывать цикл.",
      нарушения: &нарушения
    )
  }
  return корни.count
}

private func проверитьТекущееПоколениеВСохранённомДереве(
  родитель: [String: Any],
  дети: [[String: Any]],
  идентификаторПоколения: String,
  сохранённыеУзлы: [[String: Any]],
  сохранённыеРазвилки: [[String: Any]],
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  var сохранённыеПоИдентификатору: [String: [String: Any]] = [:]
  for узел in сохранённыеУзлы {
    if let идентификатор = строкаДерева(узел["идентификатор_fork"]),
      сохранённыеПоИдентификатору[идентификатор] == nil
    {
      сохранённыеПоИдентификатору[идентификатор] = узел
    }
  }
  for (индекс, текущий) in ([родитель] + дети).enumerated() {
    let идентификатор = строкаДерева(текущий["идентификатор_fork"]) ?? ""
    var нормализованный = текущий
    нормализованный.removeValue(forKey: "сторона")
    if let сохранённый = сохранённыеПоИдентификатору[идентификатор],
      равныКаноническиеЗначенияДерева(сохранённый, нормализованный)
    {
      continue
    }
    добавитьНарушениеДерева(
      "текущий_fork_не_совпадает_с_сохранённым",
      путь: индекс == 0 ? "#/паспорт/родитель" : "#/паспорт/дети/\(индекс - 1)",
      сообщение: "Текущий дескриптор fork должен точно совпадать с неизменяемым узлом дерева.",
      нарушения: &нарушения
    )
  }

  let идентификаторРодителя = строкаДерева(родитель["идентификатор_fork"]) ?? ""
  let идентификаторыДетей = дети.compactMap { строкаДерева($0["идентификатор_fork"]) }
  let совпавшиеРазвилки = сохранённыеРазвилки.filter {
    строкаДерева($0["идентификатор_поколения"]) == идентификаторПоколения
      && строкаДерева($0["идентификатор_родителя"]) == идентификаторРодителя
      && массивСтрокДерева($0["дети"]) == идентификаторыДетей
  }
  if совпавшиеРазвилки.count != 1 {
    добавитьНарушениеДерева(
      "текущая_развилка_не_сохранена",
      путь: "#/паспорт/сохранённые_развилки",
      сообщение: "Текущее поколение должно иметь одно точное неизменяемое ребро порождения.",
      нарушения: &нарушения
    )
  }
}

private func проверитьСостояниеПоколения(
  _ состояние: [String: Any],
  паспорт: [String: Any],
  сведенияПаспорта: СведенияПаспортаДерева,
  контекст: КонтекстПроверкиДереваВетвевыхФорков,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) -> СведенияСостоянияПоколения {
  let фаза = строкаДерева(состояние["фаза"]).flatMap(ФазаПоколенияВетвевогоФорка.init)
  let граница = объектДерева(состояние["родительская_граница"]) ?? [:]
  let требовалсяСодержательныйКоммит =
    логическоеДерева(граница["требовался_содержательный_коммит"]) == true
  let ожидаемоеЧислоПродолжений = требовалсяСодержательныйКоммит ? 1 : 0
  if целоеДерева(граница["число_продолжений"]) != ожидаемоеЧислоПродолжений {
    добавитьНарушениеДерева(
      "унарное_продолжение_отсутствует",
      путь: "#/состояние/родительская_граница",
      сообщение: "Содержательный коммит до развилки требует обычного единственного продолжения.",
      нарушения: &нарушения
    )
  }
  let родительскоеПродолжение = объектДерева(граница["родительское_продолжение"])
  if требовалсяСодержательныйКоммит {
    let квитанция: ДоказаннаяКвитанцияДочернегоПерехода? = родительскоеПродолжение.flatMap {
      guard let владелец = строкаДерева($0["идентификатор_владельца"]),
        let старая = строкаДерева($0["старая_вершина"]),
        let новая = строкаДерева($0["новая_вершина"]),
        let продолжение = строкаДерева($0["идентификатор_продолжения"]),
        let билет = строкаДерева($0["идентификатор_билета"]),
        let хэшКвитанции = строкаДерева($0["хэш_квитанции"])
      else { return nil }
      return ДоказаннаяКвитанцияДочернегоПерехода(
        порядок: 0,
        идентификаторРазвилки: сведенияПаспорта.идентификаторРодителя,
        идентификаторРепозитория: сведенияПаспорта.родительскийРепозиторий,
        рабочаяСсылка: сведенияПаспорта.родительскаяСсылка,
        идентификаторРабочейКопии:
          строкаДерева(сведенияПаспорта.родитель["идентификатор_checkout"]) ?? "",
        идентификаторВладельца: владелец,
        стараяВершина: старая,
        новаяВершина: новая,
        родительскиеВершины: [старая],
        видПерехода: "непосредственный_commit_handoff",
        идентификаторПродолжения: продолжение,
        идентификаторБилета: билет,
        хэшКвитанции: хэшКвитанции
      )
    }
    if квитанция == nil
      || квитанция != контекст.зафиксированнаяКвитанцияРодительскогоПродолжения
      || квитанция?.стараяВершина == квитанция?.новаяВершина
      || квитанция?.идентификаторВладельца == квитанция?.идентификаторПродолжения
      || квитанция?.новаяВершина != строкаДерева(граница["база"])
      || !валидныйОбъектДерева(
        квитанция?.стараяВершина ?? "",
        длина: сведенияПаспорта.форматОбъектов == "sha1" ? 40 : 64
      )
      || !валидныйОбъектДерева(
        квитанция?.новаяВершина ?? "",
        длина: сведенияПаспорта.форматОбъектов == "sha1" ? 40 : 64
      )
    {
      добавитьНарушениеДерева(
        "родительское_продолжение_не_доказано",
        путь: "#/состояние/родительская_граница/родительское_продолжение",
        сообщение:
          "Содержательный commit до развилки требует точную внешнюю квитанцию унарного handoff.",
        нарушения: &нарушения
      )
    }
  } else if родительскоеПродолжение != nil
    || контекст.зафиксированнаяКвитанцияРодительскогоПродолжения != nil
  {
    добавитьНарушениеДерева(
      "родительское_продолжение_не_доказано",
      путь: "#/состояние/родительская_граница/родительское_продолжение",
      сообщение:
        "Без предшествующего содержательного commit родительской квитанции быть не должно.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(граница["родительская_ссылка_неизменна"]) != true
    || строкаДерева(граница["база"])
      != сведенияПаспорта.ожидаемаяБаза
    || строкаДерева(граница["вершина"])
      != сведенияПаспорта.ожидаемаяБаза
  {
    добавитьНарушениеДерева(
      "родительская_вершина_сдвинулась",
      путь: "#/состояние/родительская_граница",
      сообщение: "Координатор не должен двигать родительский рабочий ref.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(граница["сага_сохранена"]) != true {
    добавитьНарушениеДерева(
      "сага_модерации_не_сохранена",
      путь: "#/состояние/родительская_граница",
      сообщение: "Доказанная граница саги должна быть сохранена в ref модерации.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(граница["finish_clean_выполнен"]) != true {
    добавитьНарушениеДерева(
      "родительский_finish_clean_отсутствует",
      путь: "#/состояние/родительская_граница/finish_clean_выполнен",
      сообщение: "После активации координатор должен завершить родительский FIFO без коммита.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(граница["прежняя_host_сессия_освобождена"]) != true {
    добавитьНарушениеДерева(
      "прежняя_сессия_родителя_сохранена",
      путь: "#/состояние/родительская_граница",
      сообщение: "Восстанавливаемый модератор не удерживает прежнюю host-сессию.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(граница["родительский_FIFO_освобождён"]) != true {
    добавитьНарушениеДерева(
      "родительский_FIFO_удерживается",
      путь: "#/состояние/родительская_граница",
      сообщение: "Родитель не удерживает FIFO во время работы детей.",
      нарушения: &нарушения
    )
  }

  let попыткаСреды = объектДерева(состояние["host_попытка"]) ?? [:]
  let исходСреды = строкаДерева(попыткаСреды["исход"]) ?? ""
  let привязки = массивОбъектовДерева(состояние["host_привязки"]) ?? []
  проверитьПопыткуСредыДерева(
    попыткаСреды,
    контекст: контекст,
    нарушения: &нарушения
  )
  if исходСреды == "неизвестный" {
    добавитьНарушениеДерева(
      "неизвестный_host_исход",
      путь: "#/состояние/host_попытка/исход",
      сообщение: "Неизвестный ответ не разрешает активацию и новый вызов создания.",
      нарушения: &нарушения
    )
  }
  if исходСреды == "частичный" || привязки.count != 2 {
    добавитьНарушениеДерева(
      "частичная_пара_не_активируется",
      путь: "#/состояние/host_привязки",
      сообщение: "Обе точные host-привязки должны быть доказаны до активации.",
      нарушения: &нарушения
    )
  }
  for (индекс, привязка) in привязки.enumerated() {
    if логическоеДерева(привязка["неактивна"]) != true
      || логическоеДерева(привязка["запись_разрешена"]) != false
    {
      добавитьНарушениеДерева(
        "дочерняя_привязка_получила_право_до_активации",
        путь: "#/состояние/host_привязки/\(индекс)",
        сообщение: "Подготовленная host-задача должна оставаться неактивной и непишущей.",
        нарушения: &нарушения
      )
    }
  }
  проверитьПривязкиСредыДерева(
    привязки,
    дети: сведенияПаспорта.дети,
    неактивныеДети: массивОбъектовДерева(состояние["неактивные_дети"]) ?? [],
    нарушения: &нарушения
  )
  let идентификаторПопыткиСреды = строкаДерева(попыткаСреды["идентификатор_попытки"]) ?? ""
  let идентификаторПопыткиМодерации =
    строкаДерева(сведенияПаспорта.модерация["идентификатор_попытки"]) ?? ""
  var занятыеИдентичности = Set(
    привязки.flatMap {
      [строкаДерева($0["идентификатор_thread"]), строкаДерева($0["идентификатор_host"])]
        .compactMap { $0 }
    })
  занятыеИдентичности.formUnion(сведенияПаспорта.идентификаторыДетей)
  занятыеИдентичности.insert(сведенияПаспорта.идентификаторРодителя)
  занятыеИдентичности.insert(сведенияПаспорта.идентификаторДерева)
  занятыеИдентичности.insert(сведенияПаспорта.идентификаторПоколения)
  занятыеИдентичности.insert(контекст.ожидаемыйИдентификаторМодератора)
  занятыеИдентичности.insert(контекст.ожидаемыйИдентификаторИнтегратора)
  if идентификаторПопыткиСреды.isEmpty
    || идентификаторПопыткиМодерации.isEmpty
    || идентификаторПопыткиСреды == идентификаторПопыткиМодерации
    || занятыеИдентичности.contains(идентификаторПопыткиСреды)
    || занятыеИдентичности.contains(идентификаторПопыткиМодерации)
  {
    добавитьНарушениеДерева(
      "идентификаторы_попыток_пересекаются",
      путь: "#/состояние/host_попытка/идентификатор_попытки",
      сообщение: "Host-попытка и попытка модерации должны иметь отдельные устойчивые идентичности.",
      нарушения: &нарушения
    )
  }
  let активация = объектДерева(состояние["активация_пары"]) ?? [:]
  if логическоеДерева(активация["атомарная"]) != true
    || логическоеДерева(активация["оба_ребёнка"]) != true
    || строкаДерева(активация["состояние"]) != "активирована"
  {
    добавитьНарушениеДерева(
      "частичная_активация_запрещена",
      путь: "#/состояние/активация_пары",
      сообщение: "Пара активируется одним неделимым переходом.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(активация["предактивация_сохранена"]) != true {
    добавитьНарушениеДерева(
      "граница_предактивации_не_сохранена",
      путь: "#/состояние/активация_пары",
      сообщение: "CAS активации требует сохранённую глобальную предактивационную границу.",
      нарушения: &нарушения
    )
  }
  let хэшПредактивации = строкаДерева(активация["ожидаемый_хэш_состояния"])
  if хэшПредактивации != контекст.ожидаемыйХэшПредактивации
    || хэшПредактивации != хэшПредактивацииДерева(состояние)
  {
    добавитьНарушениеДерева(
      "хэш_предактивации_не_совпадает",
      путь: "#/состояние/активация_пары/ожидаемый_хэш_состояния",
      сообщение: "Активация должна сравнивать точный сохранённый хэш глобальной предактивации.",
      нарушения: &нарушения
    )
  }

  let владельцы = массивОбъектовДерева(состояние["допуски_владельцев"]) ?? []
  var владельцыПоУзлам: [String: [[String: Any]]] = [:]
  for владелец in владельцы {
    let узел = строкаДерева(владелец["идентификатор_fork"]) ?? ""
    владельцыПоУзлам[узел, default: []].append(владелец)
  }
  for (_, допуски) in владельцыПоУзлам where допуски.count > 1 {
    добавитьНарушениеДерева(
      "две_сессии_владельца",
      путь: "#/состояние/допуски_владельцев",
      сообщение: "Один fork не может иметь более одной допущенной сессии-владельца.",
      нарушения: &нарушения
    )
    let виды = Set(допуски.compactMap { строкаДерева($0["вид"]) })
    if виды.count > 1 {
      добавитьНарушениеДерева(
        "виды_допуска_пересекаются",
        путь: "#/состояние/допуски_владельцев",
        сообщение: "Пишущий и модерирующий допуски взаимоисключаются.",
        нарушения: &нарушения
      )
    }
  }
  проверитьДопускиВладельцевДерева(
    владельцы,
    сведенияПаспорта: сведенияПаспорта,
    нарушения: &нарушения
  )
  let ожидаемаяСсылкаМодератора =
    строкаДерева(сведенияПаспорта.модерация["ссылка_состояния"]) ?? ""
  let точныйТерминальныйМодератор =
    владельцы.count == 1
    && владельцы.allSatisfy {
      строкаДерева($0["идентификатор_сессии"])
        == контекст.ожидаемыйИдентификаторМодератора
        && строкаДерева($0["идентификатор_fork"])
          == сведенияПаспорта.идентификаторРодителя
        && строкаДерева($0["вид"]) == "модерирующий"
        && строкаДерева($0["идентификатор_репозитория"])
          == сведенияПаспорта.родительскийРепозиторий
        && строкаДерева($0["целевая_ссылка"]) == ожидаемаяСсылкаМодератора
        && логическоеДерева($0["допущен"]) == true
    }
  if !точныйТерминальныйМодератор {
    добавитьНарушениеДерева(
      "терминальный_модератор_не_единственный",
      путь: "#/состояние/допуски_владельцев",
      сообщение: "Терминальный снимок допускает ровно одну сессию модератора родительского fork.",
      нарушения: &нарушения
    )
  }
  let задачиСреды = Set(привязки.compactMap { строкаДерева($0["идентификатор_thread"]) })
  let экземплярыСреды = Set(привязки.compactMap { строкаДерева($0["идентификатор_host"]) })
  let продолжения = Set(
    (массивОбъектовДерева(состояние["ожидающие_продолжения"]) ?? []).compactMap {
      строкаДерева($0["идентификатор_задачи"])
    })
  let переходыДляРолей = массивОбъектовДерева(состояние["дочерние_переходы"]) ?? []
  let владельцыПереходов = Set(
    переходыДляРолей.compactMap { строкаДерева($0["идентификатор_владельца"]) })
  let продолженияПереходов = Set(
    переходыДляРолей.compactMap { строкаДерева($0["идентификатор_продолжения"]) })
  let внешниеПроверяющие = Set(
    (массивОбъектовДерева(состояние["внешние_проверяющие"]) ?? []).compactMap {
      строкаДерева($0["идентификатор_задачи"])
    })
  let освобождённыеРодительскиеИдентичности = Set(
    [
      контекст.зафиксированнаяКвитанцияРодительскогоПродолжения?
        .идентификаторВладельца,
      контекст.зафиксированнаяКвитанцияРодительскогоПродолжения?
        .идентификаторПродолжения,
    ].compactMap { $0 })
  let пишущиеИдентичности = задачиСреды.union(продолжения).union(владельцыПереходов)
    .union(продолженияПереходов)
  let дочерниеРолевыеИдентичности = пишущиеИдентичности.union(экземплярыСреды)
    .union(внешниеПроверяющие)
  let идентификаторИнтегратора =
    строкаДерева(
      объектДерева(состояние["интеграция"])?["идентификатор_интегратора"]
    ) ?? ""
  if контекст.ожидаемыйИдентификаторМодератора.isEmpty
    || идентификаторИнтегратора.isEmpty
    || контекст.ожидаемыйИдентификаторМодератора == идентификаторИнтегратора
    || дочерниеРолевыеИдентичности.contains(контекст.ожидаемыйИдентификаторМодератора)
    || дочерниеРолевыеИдентичности.contains(идентификаторИнтегратора)
    || !внешниеПроверяющие.isDisjoint(with: пишущиеИдентичности.union(экземплярыСреды))
    || !экземплярыСреды.isDisjoint(with: пишущиеИдентичности)
    || !задачиСреды.isDisjoint(with: продолжения)
    || !освобождённыеРодительскиеИдентичности.isDisjoint(
      with: дочерниеРолевыеИдентичности.union([
        контекст.ожидаемыйИдентификаторМодератора, идентификаторИнтегратора,
      ]))
  {
    добавитьНарушениеДерева(
      "идентичности_ролей_пересекаются",
      путь: "#/состояние/допуски_владельцев",
      сообщение:
        "Модератор, интегратор, дети и внешние проверяющие должны иметь отдельные идентичности.",
      нарушения: &нарушения
    )
  }
  if фаза == .глобальнаяПредактивация || фаза == .подготовкаДетей {
    if !владельцы.isEmpty
      || !(массивОбъектовДерева(состояние["дочерние_переходы"]) ?? []).isEmpty
    {
      добавитьНарушениеДерева(
        "преждевременный_FIFO_допуск",
        путь: "#/состояние/фаза",
        сообщение: "До парной активации и освобождения родителя дети не входят в FIFO.",
        нарушения: &нарушения
      )
    }
  }

  let переходы = массивОбъектовДерева(состояние["дочерние_переходы"]) ?? []
  for (индекс, переход) in переходы.enumerated() {
    if целоеДерева(переход["число_родителей"]) != 1 {
      добавитьНарушениеДерева(
        "нелинейный_коммит",
        путь: "#/состояние/дочерние_переходы/\(индекс)",
        сообщение: "Внутри ребёнка разрешены только непосредственные однородительские коммиты.",
        нарушения: &нарушения
      )
    }
    let продолжения = целоеДерева(переход["число_продолжений"]) ?? -1
    if продолжения == 0 {
      добавитьНарушениеДерева(
        "продолжение_отсутствует",
        путь: "#/состояние/дочерние_переходы/\(индекс)",
        сообщение: "Каждый дочерний коммит требует одно заранее подтверждённое продолжение.",
        нарушения: &нарушения
      )
    } else if продолжения != 1 {
      добавитьНарушениеДерева(
        "продолжение_дублировано",
        путь: "#/состояние/дочерние_переходы/\(индекс)",
        сообщение: "Дочерний коммит не может иметь два продолжения.",
        нарушения: &нарушения
      )
    }
    if строкаДерева(переход["рабочая_ссылка"])
      == сведенияПаспорта.родительскаяСсылка
    {
      добавитьНарушениеДерева(
        "ребёнок_пишет_родительскую_цель",
        путь: "#/состояние/дочерние_переходы/\(индекс)",
        сообщение: "Ребёнок не получает право записи в родительскую цель.",
        нарушения: &нарушения
      )
    }
  }
  проверитьЛинейнуюИсториюДетейДерева(
    переходы,
    ожидающиеПродолжения: массивОбъектовДерева(
      состояние["ожидающие_продолжения"]
    ) ?? [],
    привязкиСреды: привязки,
    сведенияПаспорта: сведенияПаспорта,
    контекст: контекст,
    нарушения: &нарушения
  )
  let состояниеМодерации = объектДерева(состояние["модерация"]) ?? [:]
  let дочерниеСсылки = Set(
    сведенияПаспорта.дети.compactMap {
      строкаДерева($0["рабочая_ссылка"])
    })
  let ссылкиМодератора = Set(
    массивСтрокДерева(состояниеМодерации["ссылки_с_правом_записи"]) ?? []
  )
  if !ссылкиМодератора.isDisjoint(with: дочерниеСсылки)
    || ссылкиМодератора != Set([ожидаемаяСсылкаМодератора])
  {
    добавитьНарушениеДерева(
      "модератор_пишет_дочерний_ref",
      путь: "#/состояние/модерация/ссылки_с_правом_записи",
      сообщение: "Модератор не имеет права записи в дочерние refs.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(состояниеМодерации["идентификатор_попытки"])
    != строкаДерева(сведенияПаспорта.модерация["идентификатор_попытки"])
  {
    добавитьНарушениеДерева(
      "попытка_модерации_не_совпадает",
      путь: "#/состояние/модерация/идентификатор_попытки",
      сообщение: "Состояние модерации должно принадлежать точной попытке паспорта.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(состояниеМодерации["прежняя_host_сессия_сохранена"]) != false
    || логическоеДерева(состояниеМодерации["родительский_FIFO_удерживается"]) != false
  {
    добавитьНарушениеДерева(
      "модератор_удерживает_прежнее_владение",
      путь: "#/состояние/модерация",
      сообщение: "Восстановленный модератор не должен удерживать прежнюю host-сессию или FIFO.",
      нарушения: &нарушения
    )
  }

  let результаты = массивОбъектовДерева(состояние["замороженные_результаты"]) ?? []
  var результатыПоСторонам: [String: [String: Any]] = [:]
  for (индекс, результат) in результаты.enumerated() {
    проверитьСамохэшДерева(
      результат,
      поле: "хэш_результата",
      код: "хэш_результата_не_совпадает",
      путь: "#/состояние/замороженные_результаты/\(индекс)/хэш_результата",
      нарушения: &нарушения
    )
    if let хэшРезультата = строкаДерева(результат["хэш_результата"]),
      !контекст.зафиксированныеХэшиРезультатов.contains(хэшРезультата)
    {
      добавитьНарушениеДерева(
        "замороженный_результат_изменён",
        путь: "#/состояние/замороженные_результаты/\(индекс)",
        сообщение: "Самохэш результата должен совпадать с зафиксированным внешним якорем.",
        нарушения: &нарушения
      )
    }
    проверитьЗамороженныйРезультатДерева(
      результат,
      индекс: индекс,
      переходы: переходы,
      сведенияПаспорта: сведенияПаспорта,
      нарушения: &нарушения
    )
    if let сторона = строкаДерева(результат["сторона"]) {
      результатыПоСторонам[сторона] = результат
    }
  }
  if результаты.count != 2 || Set(результатыПоСторонам.keys) != Set(["левая", "правая"]) {
    добавитьНарушениеДерева(
      "результат_отсутствует",
      путь: "#/состояние/замороженные_результаты",
      сообщение: "Модерация требует два замороженных результата.",
      нарушения: &нарушения
    )
  }
  if контекст.зафиксированныеХэшиРезультатов.count != 2 {
    добавитьНарушениеДерева(
      "якоря_замороженных_результатов_отсутствуют",
      путь: "#/контекст/зафиксированные_хэши_результатов",
      сообщение: "Терминальная проверка требует ровно два внешних хэш-якоря результатов.",
      нарушения: &нарушения
    )
  }
  let хэшиПаспортовШагов = результаты.flatMap {
    массивСтрокДерева($0["хэши_паспортов_шагов"]) ?? []
  }
  if хэшиПаспортовШагов.count != Set(хэшиПаспортовШагов).count
    || Set(хэшиПаспортовШагов) != контекст.зафиксированныеХэшиПаспортовШагов
  {
    добавитьНарушениеДерева(
      "паспорта_шагов_результата_не_зафиксированы",
      путь: "#/контекст/зафиксированные_хэши_паспортов_шагов",
      сообщение: "Внешние якоря должны точно покрывать паспорта шагов обоих результатов.",
      нарушения: &нарушения
    )
  }
  let хэшиПроверок = результаты.flatMap { результат in
    (массивОбъектовДерева(результат["проверки"]) ?? []).compactMap {
      строкаДерева($0["хэш"])
    }
  }
  if хэшиПроверок.count != Set(хэшиПроверок).count
    || Set(хэшиПроверок) != контекст.зафиксированныеХэшиПроверок
  {
    добавитьНарушениеДерева(
      "результат_не_подтверждён_проверками",
      путь: "#/контекст/зафиксированные_хэши_проверок",
      сообщение: "Внешние якоря должны точно покрывать проверки обоих результатов.",
      нарушения: &нарушения
    )
  }
  let ссылкиРезультатов = результаты.compactMap {
    строкаДерева($0["ссылка_результата"])
  }
  if ссылкиРезультатов.count != 2 || Set(ссылкиРезультатов).count != 2 {
    добавитьНарушениеДерева(
      "ссылки_результатов_совпадают",
      путь: "#/состояние/замороженные_результаты",
      сообщение: "Каждый замороженный результат должен иметь отдельный полный ref.",
      нарушения: &нарушения
    )
  }
  let занятыеРабочиеСсылки = Set(
    [
      сведенияПаспорта.родительскаяСсылка,
      строкаДерева(сведенияПаспорта.модерация["ссылка_состояния"]) ?? "",
    ]
      + сведенияПаспорта.дети.compactMap { строкаДерева($0["рабочая_ссылка"]) }
  )
  if !Set(ссылкиРезультатов).isDisjoint(with: занятыеРабочиеСсылки) {
    добавитьНарушениеДерева(
      "ссылка_результата_пересекается_с_рабочей",
      путь: "#/состояние/замороженные_результаты",
      сообщение:
        "Refs результатов должны быть отделены от родительского, дочерних и служебного refs.",
      нарушения: &нарушения
    )
  }

  return СведенияСостоянияПоколения(
    фаза: фаза,
    результатыПоСторонам: результатыПоСторонам,
    интеграция: объектДерева(состояние["интеграция"]) ?? [:]
  )
}

private func проверитьПопыткуСредыДерева(
  _ попытка: [String: Any],
  контекст: КонтекстПроверкиДереваВетвевыхФорков,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  if целоеДерева(попытка["число_повторов"]) != 0 {
    добавитьНарушениеДерева(
      "повторное_создание_после_неопределённости",
      путь: "#/состояние/host_попытка/число_повторов",
      сообщение: "Одна сохраняемая попытка подготовки не допускает повторного вызова создания.",
      нарушения: &нарушения
    )
  }
  let авторитетное = строкаДерева(попытка["хэш_авторитетного_чтения"])
  let человеческое = строкаДерева(попытка["хэш_человеческого_восстановления"])
  if авторитетное != nil, человеческое != nil {
    добавитьНарушениеДерева(
      "восстановление_неоднозначно",
      путь: "#/состояние/host_попытка",
      сообщение: "Граница восстанавливается ровно одним видом свидетельства.",
      нарушения: &нарушения
    )
  }
  let заявленноеВосстановление: ДоказанноеВосстановлениеОтветаСреды? =
    авторитетное.map {
      ДоказанноеВосстановлениеОтветаСреды(
        вид: .авторитетноеЧтение,
        идентификаторПопытки: строкаДерева(попытка["идентификатор_попытки"]) ?? "",
        хэшКомандыПопытки: строкаДерева(попытка["хэш_команды"]) ?? "",
        хэшДоказательства: $0
      )
    }
    ?? человеческое.map {
      ДоказанноеВосстановлениеОтветаСреды(
        вид: .явноеРешениеЧеловека,
        идентификаторПопытки: строкаДерева(попытка["идентификатор_попытки"]) ?? "",
        хэшКомандыПопытки: строкаДерева(попытка["хэш_команды"]) ?? "",
        хэшДоказательства: $0
      )
    }
  if let заявленноеВосстановление,
    !контекст.доверенныеДоказательстваВосстановления.contains(
      заявленноеВосстановление
    )
  {
    добавитьНарушениеДерева(
      "восстановление_не_доказано",
      путь: "#/состояние/host_попытка",
      сообщение: "Авторитетное чтение или человеческое восстановление должно быть доверенным.",
      нарушения: &нарушения
    )
  }
}

private func проверитьПривязкиСредыДерева(
  _ привязки: [[String: Any]],
  дети: [[String: Any]],
  неактивныеДети: [[String: Any]],
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  var детиПоСторонам: [String: [String: Any]] = [:]
  for ребёнок in дети {
    if let сторона = строкаДерева(ребёнок["сторона"]) {
      детиПоСторонам[сторона] = ребёнок
    }
  }
  var встреченныеСтороны: [String] = []
  var неактивныеПоСторонам: [String: [String: Any]] = [:]
  for ребёнок in неактивныеДети {
    if let сторона = строкаДерева(ребёнок["сторона"]) {
      неактивныеПоСторонам[сторона] = ребёнок
    }
  }
  for (индекс, привязка) in привязки.enumerated() {
    let сторона = строкаДерева(привязка["сторона"]) ?? ""
    встреченныеСтороны.append(сторона)
    guard let ребёнок = детиПоСторонам[сторона] else { continue }
    if строкаДерева(привязка["идентификатор_fork"])
      != строкаДерева(ребёнок["идентификатор_fork"])
      || строкаДерева(привязка["хэш_назначения"])
        != строкаДерева(ребёнок["хэш_назначения"])
      || строкаДерева(привязка["идентификатор_thread"])?.isEmpty != false
      || строкаДерева(привязка["идентификатор_host"])?.isEmpty != false
    {
      добавитьНарушениеДерева(
        "host_привязка_не_совпадает_с_ребёнком",
        путь: "#/состояние/host_привязки/\(индекс)",
        сообщение: "Подготовленная задача должна связывать точный fork и назначение своей стороны.",
        нарушения: &нарушения
      )
    }
    let неактивныйРебёнок = неактивныеПоСторонам[сторона] ?? [:]
    if строкаДерева(неактивныйРебёнок["идентификатор_задачи"])
      != строкаДерева(привязка["идентификатор_thread"])
      || строкаДерева(неактивныйРебёнок["идентификатор_fork"])
        != строкаДерева(привязка["идентификатор_fork"])
      || логическоеДерева(неактивныйРебёнок["неактивен"]) != true
      || логическоеДерева(неактивныйРебёнок["запись_разрешена"]) != false
    {
      добавитьНарушениеДерева(
        "неактивный_ребёнок_не_связан_с_host",
        путь: "#/состояние/неактивные_дети/\(сторона)",
        сообщение: "Неактивный ребёнок должен точно связывать host-задачу своей стороны.",
        нарушения: &нарушения
      )
    }
  }
  if Set(встреченныеСтороны) != Set(["левая", "правая"])
    || встреченныеСтороны.count != 2
  {
    добавитьНарушениеДерева(
      "частичная_пара_не_активируется",
      путь: "#/состояние/host_привязки",
      сообщение: "Должны существовать ровно левая и правая неактивные привязки.",
      нарушения: &нарушения
    )
  }
  let задачи = привязки.compactMap { строкаДерева($0["идентификатор_thread"]) }
  let среды = привязки.compactMap { строкаДерева($0["идентификатор_host"]) }
  if задачи.count != 2 || Set(задачи).count != 2
    || среды.count != 2 || Set(среды).count != 2
    || неактивныеДети.count != 2
    || Set(неактивныеПоСторонам.keys) != Set(["левая", "правая"])
  {
    добавитьНарушениеДерева(
      "host_идентичности_пары_пересекаются",
      путь: "#/состояние/host_привязки",
      сообщение: "Две стороны должны иметь разные thread, host и точные неактивные свидетельства.",
      нарушения: &нарушения
    )
  }
}

private func проверитьДопускиВладельцевДерева(
  _ владельцы: [[String: Any]],
  сведенияПаспорта: СведенияПаспортаДерева,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  var узлыПоИдентификатору: [String: [String: Any]] = [
    сведенияПаспорта.идентификаторРодителя: сведенияПаспорта.родитель
  ]
  for ребёнок in сведенияПаспорта.дети {
    if let идентификатор = строкаДерева(ребёнок["идентификатор_fork"]) {
      узлыПоИдентификатору[идентификатор] = ребёнок
    }
  }
  for (индекс, владелец) in владельцы.enumerated() {
    let идентификатор = строкаДерева(владелец["идентификатор_fork"]) ?? ""
    let вид = строкаДерева(владелец["вид"]) ?? ""
    guard let узел = узлыПоИдентификатору[идентификатор] else {
      добавитьНарушениеДерева(
        "владелец_неизвестного_fork",
        путь: "#/состояние/допуски_владельцев/\(индекс)",
        сообщение: "Допуск может принадлежать только узлу текущего поколения.",
        нарушения: &нарушения
      )
      continue
    }
    let ожидаемаяСсылка =
      вид == "модерирующий"
      ? строкаДерева(сведенияПаспорта.модерация["ссылка_состояния"])
      : строкаДерева(узел["рабочая_ссылка"])
    let допустимаяРоль =
      (вид == "модерирующий" && идентификатор == сведенияПаспорта.идентификаторРодителя)
      || (вид == "пишущий" && идентификатор != сведенияПаспорта.идентификаторРодителя)
    if !допустимаяРоль
      || логическоеДерева(владелец["допущен"]) != true
      || строкаДерева(владелец["идентификатор_репозитория"])
        != строкаДерева(узел["идентификатор_репозитория"])
      || строкаДерева(владелец["целевая_ссылка"]) != ожидаемаяСсылка
    {
      добавитьНарушениеДерева(
        "допуск_не_совпадает_с_ролью",
        путь: "#/состояние/допуски_владельцев/\(индекс)",
        сообщение: "Роль, репозиторий и целевой ref допуска должны совпадать с паспортом.",
        нарушения: &нарушения
      )
    }
  }
}

private func проверитьЛинейнуюИсториюДетейДерева(
  _ переходы: [[String: Any]],
  ожидающиеПродолжения: [[String: Any]],
  привязкиСреды: [[String: Any]],
  сведенияПаспорта: СведенияПаспортаДерева,
  контекст: КонтекстПроверкиДереваВетвевыхФорков,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  let порядки = переходы.compactMap { целоеДерева($0["порядок"]) }
  let ожидаемыеПорядки = переходы.isEmpty ? [] : Array(1...переходы.count)
  if порядки != ожидаемыеПорядки {
    добавитьНарушениеДерева(
      "порядок_дочерней_истории_нарушен",
      путь: "#/состояние/дочерние_переходы",
      сообщение: "Журнал дочерних переходов должен иметь непрерывный уникальный порядок.",
      нарушения: &нарушения
    )
  }
  var детиПоИдентификатору: [String: [String: Any]] = [:]
  for ребёнок in сведенияПаспорта.дети {
    if let идентификатор = строкаДерева(ребёнок["идентификатор_fork"]) {
      детиПоИдентификатору[идентификатор] = ребёнок
    }
  }
  var переходыПоУзлам: [String: [[String: Any]]] = [:]
  var заявленныеКвитанции: [ДоказаннаяКвитанцияДочернегоПерехода] = []
  for (индекс, переход) in переходы.enumerated() {
    let идентификатор = строкаДерева(переход["идентификатор_fork"]) ?? ""
    guard let ребёнок = детиПоИдентификатору[идентификатор] else {
      добавитьНарушениеДерева(
        "переход_неизвестного_ребёнка",
        путь: "#/состояние/дочерние_переходы/\(индекс)",
        сообщение: "Линейный переход должен принадлежать ребёнку текущего поколения.",
        нарушения: &нарушения
      )
      continue
    }
    let совпадаетДескриптор =
      строкаДерева(переход["сторона"]) == строкаДерева(ребёнок["сторона"])
      && строкаДерева(переход["идентификатор_репозитория"])
        == строкаДерева(ребёнок["идентификатор_репозитория"])
      && строкаДерева(переход["рабочая_ссылка"])
        == строкаДерева(ребёнок["рабочая_ссылка"])
      && строкаДерева(переход["идентификатор_checkout"])
        == строкаДерева(ребёнок["идентификатор_checkout"])
    if !совпадаетДескриптор {
      добавитьНарушениеДерева(
        "переход_не_совпадает_с_ребёнком",
        путь: "#/состояние/дочерние_переходы/\(индекс)",
        сообщение:
          "Переход должен использовать точную сторону и неизменяемые repo/ref/checkout ребёнка.",
        нарушения: &нарушения
      )
    }
    let идентификаторПродолжения =
      строкаДерева(переход["идентификатор_продолжения"])
    let совпавшиеПродолжения = ожидающиеПродолжения.filter {
      строкаДерева($0["идентификатор_задачи"]) == идентификаторПродолжения
        && строкаДерева($0["идентификатор_fork"]) == идентификатор
        && строкаДерева($0["идентификатор_репозитория"])
          == строкаДерева(ребёнок["идентификатор_репозитория"])
        && строкаДерева($0["рабочая_ссылка"])
          == строкаДерева(ребёнок["рабочая_ссылка"])
        && строкаДерева($0["идентификатор_checkout"])
          == строкаДерева(ребёнок["идентификатор_checkout"])
        && строкаДерева($0["подтверждённая_вершина"])
          == строкаДерева(переход["новая_вершина"])
        && логическоеДерева($0["ожидает"]) == true
    }
    if целоеДерева(переход["число_продолжений"]) == 1
      && (идентификаторПродолжения?.isEmpty != false
        || совпавшиеПродолжения.count != 1)
    {
      добавитьНарушениеДерева(
        "продолжение_не_связано_с_переходом",
        путь: "#/состояние/дочерние_переходы/\(индекс)",
        сообщение: "Коммит должен иметь одно точное ожидающее продолжение от новой вершины.",
        нарушения: &нарушения
      )
    }
    if let продолжение = идентификаторПродолжения,
      let ожидающее = совпавшиеПродолжения.first,
      совпавшиеПродолжения.count == 1,
      let порядок = целоеДерева(переход["порядок"]),
      let репозиторий = строкаДерева(переход["идентификатор_репозитория"]),
      let ссылка = строкаДерева(переход["рабочая_ссылка"]),
      let рабочаяКопия = строкаДерева(переход["идентификатор_checkout"]),
      let владелец = строкаДерева(переход["идентификатор_владельца"]),
      let старая = строкаДерева(переход["старая_вершина"]),
      let новая = строкаДерева(переход["новая_вершина"]),
      let билет = строкаДерева(ожидающее["идентификатор_билета"]),
      let хэшКвитанции = строкаДерева(переход["хэш_квитанции"])
    {
      заявленныеКвитанции.append(
        ДоказаннаяКвитанцияДочернегоПерехода(
          порядок: порядок,
          идентификаторРазвилки: идентификатор,
          идентификаторРепозитория: репозиторий,
          рабочаяСсылка: ссылка,
          идентификаторРабочейКопии: рабочаяКопия,
          идентификаторВладельца: владелец,
          стараяВершина: старая,
          новаяВершина: новая,
          родительскиеВершины: [старая],
          видПерехода: "непосредственный_commit_handoff",
          идентификаторПродолжения: продолжение,
          идентификаторБилета: билет,
          хэшКвитанции: хэшКвитанции
        )
      )
    }
    переходыПоУзлам[идентификатор, default: []].append(переход)
  }
  let идентификаторыПереходов = переходы.compactMap {
    строкаДерева($0["идентификатор_продолжения"])
  }
  let идентификаторыОжидающих = ожидающиеПродолжения.compactMap {
    строкаДерева($0["идентификатор_задачи"])
  }
  let идентификаторыБилетов = ожидающиеПродолжения.compactMap {
    строкаДерева($0["идентификатор_билета"])
  }
  if идентификаторыПереходов.sorted() != идентификаторыОжидающих.sorted()
    || Set(идентификаторыПереходов).count != идентификаторыПереходов.count
    || Set(идентификаторыОжидающих).count != идентификаторыОжидающих.count
    || идентификаторыБилетов.count != ожидающиеПродолжения.count
    || Set(идентификаторыБилетов).count != идентификаторыБилетов.count
  {
    добавитьНарушениеДерева(
      "ожидающие_продолжения_не_совпадают_с_историей",
      путь: "#/состояние/ожидающие_продолжения",
      сообщение: "Снимок ожидающих продолжений должен точно покрывать дочерние коммиты.",
      нарушения: &нарушения
    )
  }
  if заявленныеКвитанции.count != переходы.count
    || Set(заявленныеКвитанции) != контекст.зафиксированныеКвитанцииПереходов
  {
    добавитьНарушениеДерева(
      "квитанции_переходов_не_доказаны",
      путь: "#/контекст/зафиксированные_квитанции_переходов",
      сообщение: "Каждый дочерний commit+handoff должен иметь точную внешнюю квитанцию перехода.",
      нарушения: &нарушения
    )
  }
  let длинаОбъекта = сведенияПаспорта.форматОбъектов == "sha1" ? 40 : 64
  var исходныеВладельцыПоУзлам: [String: String] = [:]
  for привязка in привязкиСреды {
    if let идентификатор = строкаДерева(привязка["идентификатор_fork"]),
      let владелец = строкаДерева(привязка["идентификатор_thread"])
    {
      исходныеВладельцыПоУзлам[идентификатор] = владелец
    }
  }
  for (идентификатор, история) in переходыПоУзлам {
    guard let ребёнок = детиПоИдентификатору[идентификатор] else { continue }
    var ожидаемаяСтарая = строкаДерева(ребёнок["исходная_вершина"]) ?? ""
    var ожидаемыйВладелец = исходныеВладельцыПоУзлам[идентификатор] ?? ""
    for переход in история.sorted(by: {
      (целоеДерева($0["порядок"]) ?? Int.max)
        < (целоеДерева($1["порядок"]) ?? Int.max)
    }) {
      let старая = строкаДерева(переход["старая_вершина"]) ?? ""
      let новая = строкаДерева(переход["новая_вершина"]) ?? ""
      if старая != ожидаемаяСтарая
        || старая == новая
        || !валидныйОбъектДерева(старая, длина: длинаОбъекта)
        || !валидныйОбъектДерева(новая, длина: длинаОбъекта)
      {
        добавитьНарушениеДерева(
          "дочерняя_история_непрерывна_не_полностью",
          путь: "#/состояние/дочерние_переходы/\(идентификатор)",
          сообщение: "Каждый переход должен начинаться на прежней вершине той же линейной истории.",
          нарушения: &нарушения
        )
      }
      if ожидаемыйВладелец.isEmpty
        || строкаДерева(переход["идентификатор_владельца"]) != ожидаемыйВладелец
      {
        добавитьНарушениеДерева(
          "владелец_перехода_не_связан",
          путь: "#/состояние/дочерние_переходы/\(идентификатор)",
          сообщение:
            "Первый commit принадлежит активированной host-сессии, а следующий — точному продолжению прежнего commit.",
          нарушения: &нарушения
        )
      }
      ожидаемаяСтарая = новая
      ожидаемыйВладелец = строкаДерева(переход["идентификатор_продолжения"]) ?? ""
    }
  }
}

private func проверитьЗамороженныйРезультатДерева(
  _ результат: [String: Any],
  индекс: Int,
  переходы: [[String: Any]],
  сведенияПаспорта: СведенияПаспортаДерева,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  let сторона = строкаДерева(результат["сторона"]) ?? ""
  guard
    let ребёнок = сведенияПаспорта.дети.first(where: {
      строкаДерева($0["сторона"]) == сторона
    })
  else { return }
  let идентификатор = строкаДерева(ребёнок["идентификатор_fork"]) ?? ""
  let история = переходы.filter {
    строкаДерева($0["идентификатор_fork"]) == идентификатор
  }.sorted {
    (целоеДерева($0["порядок"]) ?? Int.max)
      < (целоеДерева($1["порядок"]) ?? Int.max)
  }
  let ожидаемаяВершина =
    история.last.flatMap { строкаДерева($0["новая_вершина"]) }
    ?? строкаДерева(ребёнок["исходная_вершина"])
  let ожидаемыйДиапазон = история.compactMap {
    строкаДерева($0["новая_вершина"])
  }
  let вершина = строкаДерева(результат["вершина"])
  let диапазон = массивСтрокДерева(результат["диапазон"]) ?? []
  let хэшиПаспортовШагов = массивСтрокДерева(результат["хэши_паспортов_шагов"]) ?? []
  let проверки = массивОбъектовДерева(результат["проверки"]) ?? []
  let идентификаторыПроверок = проверки.compactMap {
    строкаДерева($0["идентификатор"])
  }
  let хэшиПроверок = проверки.compactMap { строкаДерева($0["хэш"]) }
  let точнаяСвязь =
    строкаДерева(результат["состояние"]) == "заморожен"
    && строкаДерева(результат["идентификатор_fork"]) == идентификатор
    && строкаДерева(результат["идентификатор_репозитория"])
      == строкаДерева(ребёнок["идентификатор_репозитория"])
    && строкаДерева(результат["база"])
      == строкаДерева(ребёнок["исходная_вершина"])
    && строкаДерева(результат["хэш_назначения"])
      == строкаДерева(ребёнок["хэш_назначения"])
    && строкаДерева(результат["хэш_критериев"]) == сведенияПаспорта.хэшКритериев
    && вершина == ожидаемаяВершина
    && диапазон == ожидаемыйДиапазон
  if !точнаяСвязь {
    добавитьНарушениеДерева(
      "результат_не_связан_с_ребёнком",
      путь: "#/состояние/замороженные_результаты/\(индекс)",
      сообщение:
        "Результат должен связывать точные fork, repo, базу, вершину, диапазон, назначение и критерии ребёнка.",
      нарушения: &нарушения
    )
  }
  if хэшиПаспортовШагов.isEmpty
    || Set(хэшиПаспортовШагов).count != хэшиПаспортовШагов.count
  {
    добавитьНарушениеДерева(
      "паспорта_шагов_результата_не_зафиксированы",
      путь: "#/состояние/замороженные_результаты/\(индекс)/хэши_паспортов_шагов",
      сообщение:
        "Замороженный результат должен содержать непустой уникальный набор паспортов шагов.",
      нарушения: &нарушения
    )
  }
  if проверки.isEmpty
    || идентификаторыПроверок.count != проверки.count
    || Set(идентификаторыПроверок).count != идентификаторыПроверок.count
    || хэшиПроверок.count != проверки.count
    || Set(хэшиПроверок).count != хэшиПроверок.count
    || !проверки.allSatisfy({ строкаДерева($0["исход"]) == "успешно" })
  {
    добавитьНарушениеДерева(
      "результат_не_подтверждён_проверками",
      путь: "#/состояние/замороженные_результаты/\(индекс)/проверки",
      сообщение: "Результат требует непустые уникальные успешные свидетельства проверок.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(результат["хэш_замораживания"])
    != хэшЗамораживанияРезультатаДерева(результат)
  {
    добавитьНарушениеДерева(
      "хэш_замораживания_не_совпадает",
      путь: "#/состояние/замороженные_результаты/\(индекс)/хэш_замораживания",
      сообщение: "Хэш замораживания должен покрывать точное содержимое результата до самохэша.",
      нарушения: &нарушения
    )
  }
  let расход = объектДерева(результат["расход_бюджета"]) ?? [:]
  let бюджет = объектДерева(ребёнок["бюджет"]) ?? [:]
  let превышенБюджет = ["токены", "секунды", "изменённые_файлы"].contains {
    (целоеДерева(расход[$0]) ?? Int.max) > (целоеДерева(бюджет[$0]) ?? -1)
  }
  let длинаОбъекта = сведенияПаспорта.форматОбъектов == "sha1" ? 40 : 64
  if превышенБюджет
    || !диапазон.allSatisfy({ валидныйОбъектДерева($0, длина: длинаОбъекта) })
  {
    добавитьНарушениеДерева(
      "результат_нарушает_границы",
      путь: "#/состояние/замороженные_результаты/\(индекс)",
      сообщение: "Результат обязан соблюдать формат объектов и бюджет ребёнка.",
      нарушения: &нарушения
    )
  }
}

private func валидныйОбъектДерева(_ значение: String, длина: Int) -> Bool {
  значение.count == длина
    && значение.range(of: "^[0-9a-f]+$", options: .regularExpression) != nil
}

private func проверитьРешениеИИнтеграцию(
  _ решение: [String: Any],
  состояние: [String: Any],
  паспорт: [String: Any],
  сведенияПаспорта: СведенияПаспортаДерева,
  сведенияСостояния: СведенияСостоянияПоколения,
  контекст: КонтекстПроверкиДереваВетвевыхФорков,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) -> РазрешениеСравнитьИЗаменить? {
  if контекст.зафиксированныеХэшиРешений.count != 1 {
    добавитьНарушениеДерева(
      "якорь_решения_отсутствует",
      путь: "#/контекст/зафиксированные_хэши_решений",
      сообщение: "Терминальная проверка требует ровно один внешний хэш-якорь решения.",
      нарушения: &нарушения
    )
  }
  if let хэшРешения = строкаДерева(решение["хэш_решения"]),
    !контекст.зафиксированныеХэшиРешений.contains(хэшРешения)
  {
    добавитьНарушениеДерева(
      "решение_изменено",
      путь: "#/решение/хэш_решения",
      сообщение: "Самохэш решения должен совпадать с зафиксированным внешним якорем.",
      нарушения: &нарушения
    )
  }
  let левый = сведенияСостояния.результатыПоСторонам["левая"] ?? [:]
  let правый = сведенияСостояния.результатыПоСторонам["правая"] ?? [:]
  let ссылкиНаРезультаты = объектДерева(решение["результаты"]) ?? [:]
  let левыйХэш = строкаДерева(левый["хэш_результата"]) ?? ""
  let правыйХэш = строкаДерева(правый["хэш_результата"]) ?? ""
  if строкаДерева(ссылкиНаРезультаты["левый"]) != левыйХэш
    || строкаДерева(ссылкиНаРезультаты["правый"]) != правыйХэш
    || строкаДерева(ссылкиНаРезультаты["левый"])
      == строкаДерева(ссылкиНаРезультаты["правый"])
  {
    добавитьНарушениеДерева(
      "решение_не_охватывает_обоих_детей",
      путь: "#/решение/результаты",
      сообщение: "Решение обязано ссылаться на оба точных замороженных результата.",
      нарушения: &нарушения
    )
  }
  let свидетельстваЛевого = Set(
    (массивОбъектовДерева(левый["проверки"]) ?? []).compactMap {
      строкаДерева($0["хэш"])
    })
  let свидетельстваПравого = Set(
    (массивОбъектовДерева(правый["проверки"]) ?? []).compactMap {
      строкаДерева($0["хэш"])
    })
  let заявленныеСвидетельства = массивСтрокДерева(решение["хэши_свидетельств"]) ?? []
  let множествоСвидетельств = Set(заявленныеСвидетельства)
  let группыКорреляции = массивОбъектовДерева(решение["группы_корреляции"]) ?? []
  let групповыеСвидетельства = группыКорреляции.flatMap {
    массивСтрокДерева($0["хэши_свидетельств"]) ?? []
  }
  let свидетельстваСвязаны =
    !свидетельстваЛевого.isEmpty
    && !свидетельстваПравого.isEmpty
    && множествоСвидетельств == свидетельстваЛевого.union(свидетельстваПравого)
    && заявленныеСвидетельства.count == множествоСвидетельств.count
    && группыКорреляции.count == 1
    && Set(групповыеСвидетельства) == множествоСвидетельств
    && групповыеСвидетельства.count == множествоСвидетельств.count
  if !свидетельстваСвязаны {
    добавитьНарушениеДерева(
      "свидетельства_решения_не_связаны",
      путь: "#/решение/группы_корреляции",
      сообщение:
        "Решение должно связывать все и только свидетельства проверок обоих замороженных результатов.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(решение["идентификатор_родителя"])
    != сведенияПаспорта.идентификаторРодителя
    || строкаДерева(решение["идентификатор_модератора"])
      != сведенияПаспорта.идентификаторРодителя
  {
    добавитьНарушениеДерева(
      "родитель_и_модератор_различаются",
      путь: "#/решение/идентификатор_модератора",
      сообщение: "Решение принадлежит тому же логическому родителю.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(решение["идентификатор_попытки_модерации"])
    != строкаДерева(сведенияПаспорта.модерация["идентификатор_попытки"])
  {
    добавитьНарушениеДерева(
      "попытка_модерации_не_совпадает",
      путь: "#/решение/идентификатор_попытки_модерации",
      сообщение: "Решение должно принадлежать замороженной попытке модерации.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(решение["хэш_критериев"]) != сведенияПаспорта.хэшКритериев {
    добавитьНарушениеДерева(
      "критерии_сдвинулись",
      путь: "#/решение/хэш_критериев",
      сообщение: "Сравнение аннулируется при изменении критериев.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(решение["идентификатор_дерева"])
    != сведенияПаспорта.идентификаторДерева
    || строкаДерева(решение["идентификатор_поколения"])
      != сведенияПаспорта.идентификаторПоколения
    || строкаДерева(решение["идентификатор_родительского_репозитория"])
      != сведенияПаспорта.родительскийРепозиторий
    || строкаДерева(решение["родительская_рабочая_ссылка"])
      != сведенияПаспорта.родительскаяСсылка
    || строкаДерева(решение["целевая_ссылка_интеграции"])
      != сведенияПаспорта.родительскаяСсылка
  {
    добавитьНарушениеДерева(
      "решение_не_связано_с_поколением",
      путь: "#/решение",
      сообщение: "Решение должно связывать точные дерево, поколение, репозиторий и refs родителя.",
      нарушения: &нарушения
    )
  }

  let базы = объектДерева(решение["базы"]) ?? [:]
  let вершины = объектДерева(решение["вершины"]) ?? [:]
  let ссылкиРезультатов = объектДерева(решение["ссылки_результатов"]) ?? [:]
  for (сторона, результат) in [("левая", левый), ("правая", правый)] {
    let ссылкаРезультата = строкаДерева(результат["ссылка_результата"]) ?? ""
    let вершина = строкаДерева(результат["вершина"]) ?? ""
    if строкаДерева(базы[сторона]) != строкаДерева(результат["база"])
      || строкаДерева(вершины[сторона]) != вершина
      || строкаДерева(ссылкиРезультатов[сторона]) != ссылкаРезультата
    {
      добавитьНарушениеДерева(
        "диапазон_не_совпадает",
        путь: "#/решение/\(сторона)",
        сообщение: "Решение должно связывать точные базу, вершину и ref результата.",
        нарушения: &нарушения
      )
    }
    if контекст.наблюдаемыеВершиныРезультатов[ссылкаРезультата] != вершина {
      добавитьНарушениеДерева(
        "вершина_результата_сдвинулась",
        путь: "#/решение/ссылки_результатов/\(сторона)",
        сообщение: "Сдвиг ref после сравнения аннулирует решение.",
        нарушения: &нарушения
      )
    }
  }
  if контекст.наблюдаемаяЦелеваяВершина != сведенияПаспорта.ожидаемаяБаза
    || строкаДерева(решение["ожидаемая_база"])
      != сведенияПаспорта.ожидаемаяБаза
  {
    добавитьНарушениеДерева(
      "цель_сдвинулась",
      путь: "#/решение/ожидаемая_база",
      сообщение: "Интеграция разрешена только от замороженной родительской базы.",
      нарушения: &нарушения
    )
  }

  let интеграция = сведенияСостояния.интеграция
  let интегратор = строкаДерева(интеграция["идентификатор_интегратора"]) ?? ""
  if интегратор == сведенияПаспорта.идентификаторРодителя
    || сведенияПаспорта.идентификаторыДетей.contains(интегратор)
    || интегратор != контекст.ожидаемыйИдентификаторИнтегратора
  {
    добавитьНарушениеДерева(
      "интегратор_не_отделён",
      путь: "#/состояние/интеграция/идентификатор_интегратора",
      сообщение: "Интегратор является отдельной ограждённой ролью.",
      нарушения: &нарушения
    )
  }
  if строкаДерева(интеграция["идентификатор_целевого_репозитория"])
    != сведенияПаспорта.родительскийРепозиторий
    || строкаДерева(интеграция["целевая_ссылка"])
      != сведенияПаспорта.родительскаяСсылка
    || строкаДерева(интеграция["ожидаемая_база"])
      != сведенияПаспорта.ожидаемаяБаза
  {
    добавитьНарушениеДерева(
      "неверная_цель_интеграции",
      путь: "#/состояние/интеграция",
      сообщение: "Интегратор может CAS-продвинуть только замороженную пару родителя.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(интеграция["граф_отделён"]) != true {
    добавитьНарушениеДерева(
      "интеграционный_граф_смешан_с_генеалогией",
      путь: "#/состояние/интеграция",
      сообщение: "Многородительская интеграция хранится отдельно от дерева происхождения.",
      нарушения: &нарушения
    )
  }
  if логическоеДерева(интеграция["вложенный_результат_поднят"]) != true
    || строкаДерева(интеграция["хэш_поднятого_результата"])
      != хэшПоднятогоРезультатаДерева(решение: решение, состояние: состояние)
  {
    добавитьНарушениеДерева(
      "вложенный_результат_не_поднят_вверх",
      путь: "#/состояние/интеграция",
      сообщение: "Поднятие должно связывать точные решение, оба результата и новую вершину узла.",
      нарушения: &нарушения
    )
  }

  let исход = строкаДерева(решение["исход"]) ?? ""
  let интегрируемые = Set([
    "выбран_левый_результат", "выбран_правый_результат", "совместимое_объединение",
  ])
  let состояниеСравненияИЗамены =
    строкаДерева(интеграция["состояние_сравнения_и_замены"]) ?? ""
  let идентификаторРешения = строкаДерева(решение["идентификатор_решения"]) ?? ""
  let графИнтеграции = массивОбъектовДерева(решение["граф_интеграции"]) ?? []
  let рёбраРешения = графИнтеграции.filter {
    строкаДерева($0["идентификатор_решения"]) == идентификаторРешения
  }
  if исход != "совместимое_объединение", !графИнтеграции.isEmpty {
    добавитьНарушениеДерева(
      "интеграционное_ребро_не_соответствует_исходу",
      путь: "#/решение/граф_интеграции",
      сообщение: "Многородительское ребро допустимо только для исхода совместимого объединения.",
      нарушения: &нарушения
    )
  }
  if !интегрируемые.contains(исход) {
    let ожидаемаяФаза: ФазаПоколенияВетвевогоФорка =
      исход == "неопределённость" ? .неопределён : .разрешён
    if сведенияСостояния.фаза != ожидаемаяФаза
      || состояниеСравненияИЗамены != "не_разрешено"
      || !(интеграция["предложенная_вершина"] is NSNull)
    {
      добавитьНарушениеДерева(
        "исход_не_совпадает_с_интеграцией",
        путь: "#/состояние/интеграция",
        сообщение: "Неинтегрируемый исход не должен предлагать вершину или состояние CAS.",
        нарушения: &нарушения
      )
    }
    return nil
  }
  if сведенияСостояния.фаза != .разрешён {
    добавитьНарушениеДерева(
      "исход_не_совпадает_с_интеграцией",
      путь: "#/состояние/фаза",
      сообщение: "Интегрируемое решение возможно только в разрешённой фазе.",
      нарушения: &нарушения
    )
  }
  if !контекст.предусловиеСравненияИЗаменыПодтверждено
    || состояниеСравненияИЗамены != "разрешено"
  {
    добавитьНарушениеДерева(
      "сравнение_и_замена_проиграны",
      путь: "#/состояние/интеграция/состояние_CAS",
      сообщение:
        "Декларативное CAS-разрешение требует подтверждённое предусловие, но не исполненный переход.",
      нарушения: &нарушения
    )
    return nil
  }
  let новаяВершина: String
  switch исход {
  case "выбран_левый_результат":
    новаяВершина = строкаДерева(левый["вершина"]) ?? ""
  case "выбран_правый_результат":
    новаяВершина = строкаДерева(правый["вершина"]) ?? ""
  default:
    новаяВершина = строкаДерева(интеграция["предложенная_вершина"]) ?? ""
  }
  let длинаОбъекта = сведенияПаспорта.форматОбъектов == "sha1" ? 40 : 64
  if !валидныйОбъектДерева(новаяВершина, длина: длинаОбъекта) {
    добавитьНарушениеДерева(
      "интеграционная_вершина_неверного_формата",
      путь: "#/состояние/интеграция/предложенная_вершина",
      сообщение: "Интеграционная вершина должна соответствовать формату Git-объектов паспорта.",
      нарушения: &нарушения
    )
    return nil
  }
  if строкаДерева(интеграция["предложенная_вершина"]) != новаяВершина {
    добавитьНарушениеДерева(
      "интеграционная_вершина_не_совпадает",
      путь: "#/состояние/интеграция/предложенная_вершина",
      сообщение: "Предлагаемая вершина должна точно следовать типу решения.",
      нарушения: &нарушения
    )
    return nil
  }
  if исход == "совместимое_объединение" {
    let ожидаемыеРодители = Set([
      строкаДерева(левый["вершина"]) ?? "",
      строкаДерева(правый["вершина"]) ?? "",
    ])
    let совпало =
      рёбраРешения.count == 1
      && !ожидаемыеРодители.contains(новаяВершина)
      && рёбраРешения.allSatisfy {
        Set(массивСтрокДерева($0["родительские_вершины"]) ?? [])
          == ожидаемыеРодители
          && строкаДерева($0["результирующая_вершина"]) == новаяВершина
      }
    if !совпало {
      добавитьНарушениеДерева(
        "интеграционное_ребро_не_связано_с_решением",
        путь: "#/решение/граф_интеграции",
        сообщение: "Многородительский результат должен иметь отдельное точное ребро решения.",
        нарушения: &нарушения
      )
      return nil
    }
  }
  return РазрешениеСравнитьИЗаменить(
    идентификаторИнтегратора: интегратор,
    идентификаторРепозитория: сведенияПаспорта.родительскийРепозиторий,
    целеваяСсылка: сведенияПаспорта.родительскаяСсылка,
    ожидаемаяВершина: сведенияПаспорта.ожидаемаяБаза,
    новаяВершина: новаяВершина,
    хэшРешения: строкаДерева(решение["хэш_решения"]) ?? ""
  )
}

private func проверитьОпубликованныеСхемыДерева(
  паспорт: [String: Any],
  состояние: [String: Any],
  решение: [String: Any],
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  let пары: [([String: Any], () throws -> Data, String)] = [
    (паспорт, СхемыДереваВетвевыхФорков.загрузитьПаспорт, "#/паспорт"),
    (состояние, СхемыДереваВетвевыхФорков.загрузитьСостояние, "#/состояние"),
    (решение, СхемыДереваВетвевыхФорков.загрузитьРешение, "#/решение"),
  ]
  for (документ, загрузить, путь) in пары {
    do {
      let схема = try загрузить()
      let ошибкиСхемы = ПроверкаЗакрытойСхемы.проверитьСхему(схема)
      let ошибкиДокумента = ПроверкаЗакрытойСхемы.проверитьДокумент(
        документ,
        по: схема
      )
      for ошибка in ошибкиСхемы + ошибкиДокумента {
        добавитьНарушениеДерева(
          "документ_не_соответствует_схеме",
          путь: путь + ошибка.путь,
          сообщение: ошибка.сообщение,
          нарушения: &нарушения
        )
      }
    } catch {
      добавитьНарушениеДерева(
        "схема_недоступна",
        путь: путь,
        сообщение: "Опубликованная схема недоступна: \(error)",
        нарушения: &нарушения
      )
    }
  }
}

private func разобратьДокументДерева(
  _ данные: Data,
  имя: String,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) -> [String: Any]? {
  guard !данные.isEmpty,
    данные.count <= предельныйРазмерКонтрактаДереваВетвевыхФорков
  else {
    добавитьНарушениеДерева(
      "неверный_формат_документа",
      путь: "#/\(имя)",
      сообщение: "Документ должен быть ограниченным завершённым JSON-объектом.",
      нарушения: &нарушения
    )
    return nil
  }
  var обнаружительПовторныхКлючей = JSONDuplicateKeyDetector(data: данные)
  do {
    let повторныеПути = try обнаружительПовторныхКлючей.scan()
    if !повторныеПути.isEmpty {
      for путь in повторныеПути {
        добавитьНарушениеДерева(
          "повторный_ключ",
          путь: "#/\(имя)" + путь,
          сообщение: "JSON-объект содержит повторный ключ.",
          нарушения: &нарушения
        )
      }
      return nil
    }
  } catch {
    добавитьНарушениеДерева(
      "неверный_формат_документа",
      путь: "#/\(имя)",
      сообщение: "Документ должен быть ограниченным завершённым JSON-объектом.",
      нарушения: &нарушения
    )
    return nil
  }
  guard let объект = try? JSONSerialization.jsonObject(with: данные),
    let корень = объект as? [String: Any]
  else {
    добавитьНарушениеДерева(
      "неверный_формат_документа",
      путь: "#/\(имя)",
      сообщение: "Документ должен быть ограниченным завершённым JSON-объектом.",
      нарушения: &нарушения
    )
    return nil
  }
  if let путь = путьНенормализованнойСтрокиДерева(корень) {
    добавитьНарушениеДерева(
      "строка_не_NFC",
      путь: "#/\(имя)" + путь,
      сообщение: "Ключи и строки должны быть нормализованы в NFC.",
      нарушения: &нарушения
    )
  }
  return корень
}

private func путьНенормализованнойСтрокиДерева(
  _ значение: Any,
  путь: String = "",
  глубина: Int = 0
) -> String? {
  guard глубина <= 256 else { return путь }
  if let строка = значение as? String {
    let нормализованная = строка.precomposedStringWithCanonicalMapping
    return строка.utf8.elementsEqual(нормализованная.utf8) ? nil : путь
  }
  if let объект = значение as? [String: Any] {
    for ключ in объект.keys.sorted() {
      let путьКлюча = путь + "#/" + ключ
      let нормализованныйКлюч = ключ.precomposedStringWithCanonicalMapping
      if !ключ.utf8.elementsEqual(нормализованныйКлюч.utf8) { return путьКлюча }
      if let вложенный = объект[ключ],
        let найденный = путьНенормализованнойСтрокиДерева(
          вложенный,
          путь: путьКлюча,
          глубина: глубина + 1
        )
      {
        return найденный
      }
    }
  } else if let массив = значение as? [Any] {
    for (индекс, вложенный) in массив.enumerated() {
      if let найденный = путьНенормализованнойСтрокиДерева(
        вложенный,
        путь: путь + "#/\(индекс)",
        глубина: глубина + 1
      ) {
        return найденный
      }
    }
  }
  return nil
}

func каноническиеДанныеДерева(_ значение: Any) throws -> Data {
  try JSONSerialization.data(
    withJSONObject: значение,
    options: [.sortedKeys, .withoutEscapingSlashes]
  )
}

func хэшПроизвольногоЗначенияДерева(_ значение: Any) -> String {
  guard let данные = try? каноническиеДанныеДерева(значение) else { return "" }
  return "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}

func хэшОбъектаДерева(_ объект: [String: Any], исключая поле: String) -> String {
  var копия = объект
  копия.removeValue(forKey: поле)
  return хэшПроизвольногоЗначенияДерева(копия)
}

func хэшЗамораживанияРезультатаДерева(_ результат: [String: Any]) -> String {
  var содержимое = результат
  содержимое.removeValue(forKey: "хэш_результата")
  содержимое.removeValue(forKey: "хэш_замораживания")
  return хэшПроизвольногоЗначенияДерева(содержимое)
}


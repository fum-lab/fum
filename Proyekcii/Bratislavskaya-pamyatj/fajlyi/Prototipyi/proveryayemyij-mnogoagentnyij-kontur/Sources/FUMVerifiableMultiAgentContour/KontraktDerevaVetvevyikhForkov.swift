public enum ПроверкаДереваВетвевыхФорков {
  public static func проверить(
    паспорт данныеПаспорта: Data,
    состояние данныеСостояния: Data,
    решение данныеРешения: Data,
    контекст: КонтекстПроверкиДереваВетвевыхФорков
  ) -> ОтчётПроверкиДереваВетвевыхФорков {
    var нарушения: [НарушениеПроверкиДереваВетвевыхФорков] = []
    guard
      let паспорт = разобратьДокументДерева(
        данныеПаспорта,
        имя: "паспорт",
        нарушения: &нарушения
      ),
      let состояние = разобратьДокументДерева(
        данныеСостояния,
        имя: "состояние",
        нарушения: &нарушения
      ),
      let решение = разобратьДокументДерева(
        данныеРешения,
        имя: "решение",
        нарушения: &нарушения
      )
    else {
      return сформироватьОтчётДерева(
        фаза: nil,
        числоКорней: 0,
        числоУзлов: 0,
        разрешениеСравнитьИЗаменить: nil,
        нарушения: нарушения
      )
    }

    проверитьОпубликованныеСхемыДерева(
      паспорт: паспорт,
      состояние: состояние,
      решение: решение,
      нарушения: &нарушения
    )
    проверитьСамохэшДерева(
      паспорт,
      поле: "хэш_паспорта",
      код: "хэш_паспорта_не_совпадает",
      путь: "#/паспорт/хэш_паспорта",
      нарушения: &нарушения
    )
    проверитьСамохэшДерева(
      состояние,
      поле: "хэш_состояния",
      код: "хэш_состояния_не_совпадает",
      путь: "#/состояние/хэш_состояния",
      нарушения: &нарушения
    )
    проверитьСамохэшДерева(
      решение,
      поле: "хэш_решения",
      код: "хэш_решения_не_совпадает",
      путь: "#/решение/хэш_решения",
      нарушения: &нарушения
    )

    let паспортныйХэш = строкаДерева(паспорт["хэш_паспорта"])
    if паспортныйХэш != контекст.зафиксированныйХэшПаспорта {
      добавитьНарушениеДерева(
        "якорь_паспорта_не_совпадает",
        путь: "#/контекст/зафиксированный_хэш_паспорта",
        сообщение: "Терминальная проверка требует внешний хэш-якорь точного паспорта.",
        нарушения: &нарушения
      )
    }
    let хэшСостояния = строкаДерева(состояние["хэш_состояния"]) ?? ""
    if контекст.зафиксированныеХэшиСостояний.count != 1
      || !контекст.зафиксированныеХэшиСостояний.contains(хэшСостояния)
    {
      добавитьНарушениеДерева(
        "якорь_состояния_не_совпадает",
        путь: "#/контекст/зафиксированные_хэши_состояний",
        сообщение: "Терминальная проверка требует ровно один внешний хэш-якорь состояния.",
        нарушения: &нарушения
      )
    }
    let хэшКритериев = строкаДерева(
      объектДерева(паспорт["модерация"])?["хэш_критериев"]
    )
    if хэшКритериев != контекст.зафиксированныйХэшКритериев {
      добавитьНарушениеДерева(
        "якорь_критериев_не_совпадает",
        путь: "#/контекст/зафиксированный_хэш_критериев",
        сообщение: "Критерии модерации должны совпадать с внешним неизменяемым якорем.",
        нарушения: &нарушения
      )
    }
    if строкаДерева(состояние["хэш_паспорта"]) != паспортныйХэш
      || строкаДерева(решение["хэш_паспорта"]) != паспортныйХэш
    {
      добавитьНарушениеДерева(
        "хэш_паспорта_не_связан",
        путь: "",
        сообщение: "Состояние и решение должны ссылаться на точный паспорт.",
        нарушения: &нарушения
      )
    }

    let сведенияПаспорта = проверитьПаспортДерева(
      паспорт,
      контекст: контекст,
      нарушения: &нарушения
    )
    let сведенияСостояния = проверитьСостояниеПоколения(
      состояние,
      паспорт: паспорт,
      сведенияПаспорта: сведенияПаспорта,
      контекст: контекст,
      нарушения: &нарушения
    )
    let разрешение = проверитьРешениеИИнтеграцию(
      решение,
      состояние: состояние,
      паспорт: паспорт,
      сведенияПаспорта: сведенияПаспорта,
      сведенияСостояния: сведенияСостояния,
      контекст: контекст,
      нарушения: &нарушения
    )

    return сформироватьОтчётДерева(
      фаза: сведенияСостояния.фаза,
      числоКорней: сведенияПаспорта.числоКорней,
      числоУзлов: сведенияПаспорта.числоУзлов,
      разрешениеСравнитьИЗаменить: нарушения.isEmpty ? разрешение : nil,
      нарушения: нарушения
    )
  }
}


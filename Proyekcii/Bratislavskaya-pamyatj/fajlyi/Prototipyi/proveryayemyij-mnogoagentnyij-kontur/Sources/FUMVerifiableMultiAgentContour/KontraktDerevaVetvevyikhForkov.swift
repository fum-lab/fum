func целоеДерева(_ значение: Any?) -> Int? {
  guard let число = значение as? NSNumber,
    CFGetTypeID(число) != CFBooleanGetTypeID(),
    число.doubleValue.rounded() == число.doubleValue
  else { return nil }
  return число.intValue
}

func логическоеДерева(_ значение: Any?) -> Bool? {
  guard let число = значение as? NSNumber,
    CFGetTypeID(число) == CFBooleanGetTypeID()
  else { return nil }
  return число.boolValue
}

func равныКаноническиеЗначенияДерева(_ левое: Any, _ правое: Any) -> Bool {
  guard
    let левыеДанные = try? каноническиеДанныеДерева(левое),
    let правыеДанные = try? каноническиеДанныеДерева(правое)
  else { return false }
  return левыеДанные == правыеДанные
}

func хэшПоднятогоРезультатаДерева(
  решение: [String: Any],
  состояние: [String: Any]
) -> String {
  let интеграция = объектДерева(состояние["интеграция"]) ?? [:]
  let результаты = массивОбъектовДерева(состояние["замороженные_результаты"]) ?? []
  var хэшиПоСторонам: [String: String] = [:]
  for результат in результаты {
    if let сторона = строкаДерева(результат["сторона"]),
      let хэш = строкаДерева(результат["хэш_результата"])
    {
      хэшиПоСторонам[сторона] = хэш
    }
  }
  return хэшПроизвольногоЗначенияДерева([
    "идентификатор_решения": решение["идентификатор_решения"] ?? NSNull(),
    "хэш_решения": решение["хэш_решения"] ?? NSNull(),
    "исход": решение["исход"] ?? NSNull(),
    "результаты": хэшиПоСторонам,
    "предложенная_вершина": интеграция["предложенная_вершина"] ?? NSNull(),
  ])
}

private func проверитьСамохэшДерева(
  _ объект: [String: Any],
  поле: String,
  код: String,
  путь: String,
  нарушения: inout [НарушениеПроверкиДереваВетвевыхФорков]
) {
  if строкаДерева(объект[поле]) != хэшОбъектаДерева(объект, исключая: поле) {
    добавитьНарушениеДерева(
      код,
      путь: путь,
      сообщение: "Самохэш не совпадает с каноническим содержимым объекта.",
      нарушения: &нарушения
    )
  }
}

private func сформироватьОтчётДерева(
  фаза: ФазаПоколенияВетвевогоФорка?,
  числоКорней: Int,
  числоУзлов: Int,
  разрешениеСравнитьИЗаменить: РазрешениеСравнитьИЗаменить?,
  нарушения: [НарушениеПроверкиДереваВетвевыхФорков]
) -> ОтчётПроверкиДереваВетвевыхФорков {
  let упорядоченные = Array(Set(нарушения)).sorted {
    ($0.путь, $0.код, $0.сообщение) < ($1.путь, $1.код, $1.сообщение)
  }
  return ОтчётПроверкиДереваВетвевыхФорков(
    решение: упорядоченные.isEmpty ? .допустимо : .недопустимо,
    фаза: фаза,
    числоКорней: числоКорней,
    числоУзлов: числоУзлов,
    разрешениеСравнитьИЗаменить: упорядоченные.isEmpty
      ? разрешениеСравнитьИЗаменить : nil,
    нарушения: упорядоченные
  )
}

private func добавитьНарушениеДерева(
  _ код: String,

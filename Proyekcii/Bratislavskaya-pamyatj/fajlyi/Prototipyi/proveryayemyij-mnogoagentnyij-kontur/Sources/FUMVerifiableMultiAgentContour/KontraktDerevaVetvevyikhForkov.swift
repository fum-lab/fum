private let предельныйРазмерКонтрактаДереваВетвевыхФорков = 1_048_576

public enum ОшибкаСхемДереваВетвевыхФорков: Error, Sendable {
  case ресурсОтсутствует(String)
  case ресурсСлишкомВелик(String, Int)
}

public enum СхемыДереваВетвевыхФорков {
  public static func загрузитьПаспорт() throws -> Data {
    try загрузить("схема-паспорта-дерева-ветвевых-форков-v1")
  }

  public static func загрузитьСостояние() throws -> Data {
    try загрузить("схема-состояния-поколения-ветвевого-форка-v1")
  }

  public static func загрузитьРешение() throws -> Data {
    try загрузить("схема-решения-модератора-v1")
  }

  private static func загрузить(_ имя: String) throws -> Data {
    let прямойАдрес = Bundle.module.resourceURL?
      .appendingPathComponent("Фикстуры", isDirectory: true)
      .appendingPathComponent("ДеревоВетвевыхФорков", isDirectory: true)
      .appendingPathComponent(имя)
      .appendingPathExtension("json")
    let адрес =
      (прямойАдрес.flatMap {
        FileManager.default.fileExists(atPath: $0.path) ? $0 : nil
      })
      ?? Bundle.module.url(
        forResource: имя,
        withExtension: "json",
        subdirectory: "Фикстуры/ДеревоВетвевыхФорков"
      )
      ?? Bundle.module.url(
        forResource: имя,
        withExtension: "json",
        subdirectory: "ДеревоВетвевыхФорков"
      )
      ?? Bundle.module.url(forResource: имя, withExtension: "json")
    guard let адрес else {
      throw ОшибкаСхемДереваВетвевыхФорков.ресурсОтсутствует(имя)
    }
    let значения = try адрес.resourceValues(forKeys: [.fileSizeKey])
    guard let размер = значения.fileSize,
      размер <= предельныйРазмерКонтрактаДереваВетвевыхФорков
    else {
      throw ОшибкаСхемДереваВетвевыхФорков.ресурсСлишкомВелик(
        имя,
        значения.fileSize ?? -1
      )
    }
    let данные = try Data(contentsOf: адрес, options: [.mappedIfSafe])
    guard данные.count <= предельныйРазмерКонтрактаДереваВетвевыхФорков else {
      throw ОшибкаСхемДереваВетвевыхФорков.ресурсСлишкомВелик(имя, данные.count)
    }
    return данные
  }
}


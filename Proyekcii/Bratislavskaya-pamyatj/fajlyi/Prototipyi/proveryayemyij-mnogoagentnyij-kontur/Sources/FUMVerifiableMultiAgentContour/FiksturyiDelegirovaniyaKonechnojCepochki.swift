  private static func добавитьХэш(
    _ исходный: [String: Any],
    поле: String
  ) throws -> [String: Any] {
    var результат = исходный
    результат.removeValue(forKey: поле)
    let данные = try сериализовать(результат)
    результат[поле] =
      "sha256:"
      + SHA256.hash(data: данные).map {
        String(format: "%02x", $0)
      }.joined()
    return результат
  }

  private static func сериализовать(_ объект: [String: Any]) throws -> Data {
    guard JSONSerialization.isValidJSONObject(объект) else {
      throw ОшибкаФикстурыДелегированияКонечнойЦепочки.неканоническийОбъект
    }
    return try JSONSerialization.data(
      withJSONObject: объект,
      options: [.sortedKeys, .withoutEscapingSlashes]
    )
  }

  private static func повтор(_ значение: String, длина: Int) -> String {
    String(repeating: значение, count: длина)
  }

import Foundation
import XCTest

@testable import ДеревоДокументовЯдро

final class ТестыРаскладчикаДерева: XCTestCase {
  func test_размещаетЛистьяСлеваНаправоИЦентрируетРодителей() {
    let снимок = снимокДляРаскладки()
    let результат = РаскладчикДерева(
      горизонтальныйШаг: 10,
      вертикальныйШаг: 20
    ).разложить(снимок: снимок)

    XCTAssertEqual(
      результат.видимыеИдентификаторы,
      [".", "а", "а/1.md", "а/2.md", "б", "б/3.md"]
    )
    XCTAssertEqual(
      результат.положения["а/1.md"],
      ТочкаДерева(поГоризонтали: 5, поВертикали: 50)
    )
    XCTAssertEqual(
      результат.положения["а/2.md"],
      ТочкаДерева(поГоризонтали: 15, поВертикали: 50)
    )
    XCTAssertEqual(
      результат.положения["б/3.md"],
      ТочкаДерева(поГоризонтали: 25, поВертикали: 50)
    )
    XCTAssertEqual(
      результат.положения["а"],
      ТочкаДерева(поГоризонтали: 10, поВертикали: 30)
    )
    XCTAssertEqual(
      результат.положения["б"],
      ТочкаДерева(поГоризонтали: 25, поВертикали: 30)
    )
    XCTAssertEqual(
      результат.положения["."],
      ТочкаДерева(поГоризонтали: 17.5, поВертикали: 10)
    )
    XCTAssertEqual(результат.ширина, 30)
    XCTAssertEqual(результат.высота, 60)
    XCTAssertEqual(результат.рёбра.count, результат.видимыеИдентификаторы.count - 1)
    проверитьЕдинственногоРодителя(в: результат)
  }

  func test_свёрнутыйУзелСкрываетВсехПотомков() {
    let результат = РаскладчикДерева(
      горизонтальныйШаг: 10,
      вертикальныйШаг: 20
    ).разложить(снимок: снимокДляРаскладки(), свёрнутые: ["а"])

    XCTAssertEqual(результат.видимыеИдентификаторы, [".", "а", "б", "б/3.md"])
    XCTAssertNil(результат.положения["а/1.md"])
    XCTAssertNil(результат.положения["а/2.md"])
    XCTAssertEqual(
      результат.положения["а"],
      ТочкаДерева(поГоризонтали: 5, поВертикали: 30)
    )
    XCTAssertEqual(
      результат.положения["б/3.md"],
      ТочкаДерева(поГоризонтали: 15, поВертикали: 50)
    )
    XCTAssertEqual(
      результат.положения["."],
      ТочкаДерева(поГоризонтали: 10, поВертикали: 10)
    )
    XCTAssertEqual(результат.ширина, 20)
    XCTAssertEqual(результат.высота, 60)
    XCTAssertEqual(результат.рёбра.count, результат.видимыеИдентификаторы.count - 1)
    проверитьЕдинственногоРодителя(в: результат)
  }

  func test_повторныйИдентификаторНеСоздаётВтороеРебро() {
    let исходныйСнимок = снимокДляРаскладки()
    let снимокСПовтором = СнимокДерева(
      корень: исходныйСнимок.корень,
      узлы: исходныйСнимок.узлы + [
        узел(
          идентификаторУзла: "а/1.md",
          родитель: "а",
          вид: .документ,
          глубина: 2
        )
      ],
      числоДокументов: исходныйСнимок.числоДокументов
    )

    let результат = РаскладчикДерева().разложить(снимок: снимокСПовтором)

    XCTAssertEqual(Set(результат.видимыеИдентификаторы).count, 6)
    XCTAssertEqual(результат.видимыеИдентификаторы.count, 6)
    XCTAssertEqual(результат.рёбра.count, 5)
    проверитьЕдинственногоРодителя(в: результат)
  }
}

private func снимокДляРаскладки() -> СнимокДерева {
  СнимокДерева(
    корень: URL(fileURLWithPath: "временный-корень"),
    узлы: [
      узел(идентификаторУзла: "б/3.md", родитель: "б", вид: .документ, глубина: 2),
      узел(идентификаторУзла: ".", родитель: nil, вид: .корень, глубина: 0),
      узел(идентификаторУзла: "а/2.md", родитель: "а", вид: .документ, глубина: 2),
      узел(идентификаторУзла: "б", родитель: ".", вид: .каталог, глубина: 1),
      узел(идентификаторУзла: "а", родитель: ".", вид: .каталог, глубина: 1),
      узел(идентификаторУзла: "а/1.md", родитель: "а", вид: .документ, глубина: 2),
    ],
    числоДокументов: 3
  )
}

private func узел(
  идентификаторУзла: String,
  родитель: String?,
  вид: ВидУзлаДерева,
  глубина: Int
) -> УзелДерева {
  УзелДерева(
    идентификатор: идентификаторУзла,
    название: идентификаторУзла,
    относительныйПуть: идентификаторУзла,
    родитель: родитель,
    вид: вид,
    глубина: глубина,
    числоСсылок: 0
  )
}

private func проверитьЕдинственногоРодителя(в результат: РезультатРаскладки) {
  for идентификатор in результат.видимыеИдентификаторы where идентификатор != "." {
    XCTAssertEqual(результат.рёбра.filter { $0.к == идентификатор }.count, 1)
  }
}

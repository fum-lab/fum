import json
import os
import re
import stat
import sys
from pathlib import Path


КОРЕНЬ_КОДА = Path(__file__).resolve().parents[3]


def загрузить_модуль(имя, путь):
    описание = importlib.util.spec_from_file_location(имя, путь)
    модуль = importlib.util.module_from_spec(описание)
    sys.modules[имя] = модуль
    описание.loader.exec_module(модуль)
    return модуль


ИНДЕКС = загрузить_модуль("индекс_readme_внимания", КОРЕНЬ_КОДА / "Инструменты/fum-indeks-readme/scripts/check-readme-index.py")
СВЕЖЕСТЬ = загрузить_модуль("свежесть_readme_внимания", КОРЕНЬ_КОДА / "Инструменты/fum-svezhestj-markdown/scripts/update-md-recency.py")


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def канонические_байты(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()


def разобрать_json(байты):
    def пары(элементы):
        результат = {}
        for ключ, значение in элементы:
            if ключ in результат:
                raise ValueError("Повторное поле JSON")
            результат[ключ] = значение
        return результат
    if len(байты) > 262144:
        raise ValueError("Превышен предел JSON")
    return json.loads(байты, object_pairs_hook=пары)


def источник_проверки():
    пути = [Path(__file__).resolve(), Path(ИНДЕКС.__file__), Path(СВЕЖЕСТЬ.__file__)]
    файлы = {путь.relative_to(КОРЕНЬ_КОДА).as_posix(): хэш(путь.read_bytes()) for путь in пути}
    return {"схема": "fum.источник-проверки-ссылки.1", "файлы": файлы, "хэш": хэш(канонические_байты(файлы))}


def проверить_ссылку(вход, цель):
    """Отдельная проверка конечного критерия; не вычисляет состояние потребности."""
    try:
        readme = вход["факты"]["readme"]
        байты = вход["источники"]["README.md"]["текст"].encode("utf-8")
        основание = вход["факты"]["зависимости"][цель]
        ссылки = извлечь_ссылки(байты)
        срез = {"хэшИсточника": хэш(байты), "ссылки": ссылки, "цели": [ссылка["цель"] for ссылка in ссылки]}
        if (хэш(байты) != readme["хэш"] or readme["хэш"] != readme["текущийХэш"]
                or срез != readme["срез"] or основание["хэш"] != основание["текущийХэш"]):
            raise ValueError("Текущее свидетельство не связано с байтами")
        return {"схема": "fum.проверка-критерия.1", "критерий": "прямая-ссылка.1",
                "исход": "соответствует" if цель in срез["цели"] else "расхождение",
                "репозиторий": вход["факты"]["репозиторий"], "цель": цель,
                "readmeХэш": хэш(байты), "срезХэш": хэш(канонические_байты(срез)),
                "основаниеХэш": основание["хэш"], "прежнийХэш": вход["прежнее"]["основания"]["readmeХэш"],
                "время": вход["факты"]["время"], "проверяющий": источник_проверки()}
    except (KeyError, TypeError, AttributeError) as ошибка:
        raise ValueError("Недостаточно фактов для проверки ссылки") from ошибка


def видимые_символы(текст):
    """Та же конечная область Markdown, с пробелами вместо удаления диапазонов."""
    результат = list(текст)
    for совпадение in re.finditer(r"<!--(?:.|\n)*?(?:-->|\Z)", текст):
        for номер in range(*совпадение.span()):
            if результат[номер] not in "\r\n":
                результат[номер] = " "
    смещение = 0
    видимые_строки = ИНДЕКС.mask_invisible_markdown(текст)
    for номер_строки, строка in enumerate("".join(результат).splitlines(keepends=True)):
        if not видимые_строки[номер_строки].strip():
            for номер in range(смещение, смещение + len(строка)):
                if результат[номер] not in "\r\n":
                    результат[номер] = " "
        смещение += len(строка)
    return ИНДЕКС.mask_inline_code("".join(результат))


def извлечь_ссылки(байты):
    if len(байты) > 262144:
        raise ValueError("README превышает конечный предел байтов")
    текст = байты.decode("utf-8")
    видимое = видимые_символы(текст)
    границы = [0]
    for символ in текст:
        границы.append(границы[-1] + len(символ.encode()))
    ссылки = []
    for совпадение in ИНДЕКС.MARKDOWN_LINK_RE.finditer(видимое):
        цель = ИНДЕКС.normalized_root_target(совпадение[1])
        if цель is None:
            continue
        начало, конец = (границы[номер] for номер in совпадение.span())
        ссылки.append({"цель": цель, "начало": начало, "конец": конец,
                       "хэшДиапазона": хэш(байты[начало:конец]), "хэшИсточника": хэш(байты)})
    # Независимая существующая семантика видимости не даёт позиции байтов.
    if set(ссылка["цель"] for ссылка in ссылки) != ИНДЕКС.видимые_цели_ссылок(текст):
        raise ValueError("Разбор ссылок не совпал с поддержанной областью индекса")
    if len(ссылки) > 128:
        raise ValueError("Слишком много ссылок")
    return ссылки


def прочитать_обычный(корень, имя):
    путь = Path(имя)
    if путь.is_absolute() or ".." in путь.parts:
        raise ValueError("Нужен внутренний относительный путь")
    текущий = корень
    for часть in путь.parts:
        if часть not in os.listdir(текущий):
            raise ValueError("Нет точного имени компонента")
        текущий /= часть
        if текущий.is_symlink():
            raise ValueError("Символическая ссылка не является исходным файлом")
    if not stat.S_ISREG(текущий.stat(follow_symlinks=False).st_mode):
        raise ValueError("Источник не является обычным файлом")
    номер = os.open(текущий, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(номер, "rb") as поток:
        if not stat.S_ISREG(os.fstat(поток.fileno()).st_mode):
            raise ValueError("Источник не является обычным файлом")
        байты = поток.read(262145)
    if len(байты) > 262144:
        raise ValueError("Источник превышает конечный предел")
    return байты


def факт_файла(корень, имя):
    try:
        байты = прочитать_обычный(корень, имя)
        содержимое, метка, повреждение = СВЕЖЕСТЬ.split_recency_block(байты.decode("utf-8"))
        вычисленный = СВЕЖЕСТЬ.content_digest(СВЕЖЕСТЬ.canonical_content(содержимое))
        return {"путь": имя, "доступность": "доступен", "хэш": хэш(байты),
                "blob": hashlib.sha1(b"blob " + str(len(байты)).encode() + b"\0" + байты).hexdigest(),
                "размер": len(байты), "хэшСодержимого": вычисленный,
                "recencyХэш": метка.digest if метка else "отсутствует",
                "recencyВремя": метка.timestamp if метка else "отсутствует",
                "recencyФормат": "повреждён" if повреждение else "распознан"}, байты
    except (OSError, ValueError, UnicodeError):
        return {"путь": имя, "доступность": "недоступен"}, None


def собрать_readme(корень, репозиторий, задача, время, прежнее=None, обратная_связь=None):
    if прежнее is not None and (not isinstance(прежнее, dict) or set(прежнее) != {"состояние", "причина", "область", "основания"}):
        raise ValueError("Неверное прежнее состояние")
    if обратная_связь is not None and (not isinstance(обратная_связь, dict) or set(обратная_связь) != {"рассмотрение", "проверка"}):
        raise ValueError("Неверная обратная связь")
    корень = Path(корень).resolve()
    readme, байты = факт_файла(корень, "README.md")
    зависимости = {}
    источники = {"README.md": dict(readme), "проверяющий": источник_проверки()}
    if байты is not None:
        источники["README.md"]["текст"] = байты.decode("utf-8")
    for имя in ("Приложения/FUMA/README.md", "Документация/README.md"):
        факт, _ = факт_файла(корень, имя)
        зависимости[имя] = факт
        источники[имя] = dict(факт)
    if байты is not None:
        try:
            ссылки = извлечь_ссылки(байты)
            # Полный прочитанный исходник, а не только положительные совпадения,
            # позволяет определению проверить отсутствие обязательного адреса.
            readme.update({"цели": [ссылка["цель"] for ссылка in ссылки], "ссылки": ссылки,
                           "срезХэш": хэш(байты), "срезРазмер": len(байты), "разбор": "полный"})
            readme["срез"] = {"хэшИсточника": хэш(байты), "ссылки": ссылки, "цели": readme["цели"]}
            источники["извлечение"] = {"хэш": хэш(канонические_байты(readme["срез"])),
                                     "хэшИсточника": хэш(байты), "разбор": "сверен с индексом"}
        except ValueError:
            readme["разбор"] = "неподдержан"
        текущий, _ = факт_файла(корень, "README.md")
        readme["текущийХэш"] = текущий.get("хэш", "недоступен")
    for имя, факт in зависимости.items():
        текущий, _ = факт_файла(корень, имя)
        факт["текущийХэш"] = текущий.get("хэш", "недоступен")
    результат = {"схема": "fum.структурированный-вход.2",
            "факты": {"репозиторий": репозиторий, "задача": задача, "время": время,
                       "readme": readme, "зависимости": зависимости},
            "источники": источники,
            "прежнее": прежнее if прежнее is not None else {"состояние": "нет", "причина": "", "область": "", "основания": {}},
            "обратнаяСвязь": обратная_связь if обратная_связь is not None else {"рассмотрение": "не рассмотрено", "проверка": {}}}
    проверка = результат["обратнаяСвязь"]["проверка"]
    if проверка:
        try:
            if проверить_ссылку(результат, проверка["цель"]) == проверка:
                результат["источники"]["проверка"] = проверка
        except (ValueError, KeyError, TypeError):
            pass  # Отсутствующая привязка останется видна обязательному условию графа.
    return результат


def главный():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--корень-репозитория", required=True, type=Path)
    парсер.add_argument("--репозиторий", required=True)
    парсер.add_argument("--задача", required=True)
    парсер.add_argument("--время", required=True)
    парсер.add_argument("--прежнее", type=Path)
    парсер.add_argument("--обратная-связь", type=Path)
    парсер.add_argument("--проверить-результат", choices=["Приложения/FUMA/README.md", "Документация/README.md"])
    параметры = парсер.parse_args()
    прежнее = разобрать_json(параметры.прежнее.read_bytes()) if параметры.прежнее else None
    связь = разобрать_json(параметры.обратная_связь.read_bytes()) if параметры.обратная_связь else None
    результат = собрать_readme(параметры.корень_репозитория, параметры.репозиторий, параметры.задача, параметры.время, прежнее, связь)
    if параметры.проверить_результат:
        проверка = проверить_ссылку(результат, параметры.проверить_результат)
        результат["обратнаяСвязь"]["проверка"] = проверка
        результат["источники"]["проверка"] = проверка
    print(канонические_байты(результат).decode())


if __name__ == "__main__":
    главный()

import закрытый_отчёт_из_гита as проверяющий


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def источник_проверяющего():
    пути = ["закрытый_отчёт_из_гита.py", "связь_отпечатка_с_коммитом.py", "отчёты_о_запусках_проверок.py"]
    каталог = КОРЕНЬ / "Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts"
    файлы = {"Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts/" + имя: хэш((каталог / имя).read_bytes()) for имя in пути}
    for имя in ("объекты_внимания.py", "интеграция_внимания.py"):
        путь = КАТАЛОГ / имя
        файлы[путь.relative_to(КОРЕНЬ).as_posix()] = хэш(путь.read_bytes())
    return {"контракт": "fum.проверенный-отчёт.1", "файлы": файлы,
            "хэш": хэш(json.dumps(файлы, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode())}


def извлечь_приёмку(чтение, коммит, запрос, корень_гит):
    сессия = проверяющий.папка_запроса(запрос)
    номер_запроса, байты_запроса = чтение.файл(коммит, запрос)
    номер_отчёта, байты_отчёта = чтение.файл(коммит, сессия + "/отчёт.md")
    файлы = чтение.файлы_каталога(коммит, сессия + "/материалы/запуски-проверок")
    источник = источник_проверяющего()
    общие = {"коммит": коммит, "дерево": чтение.коммит(коммит)["дерево"], "запрос": запрос,
             "blobЗапроса": номер_запроса, "хэшЗапроса": хэш(байты_запроса), "blobОтчёта": номер_отчёта,
             "хэшОтчёта": хэш(байты_отчёта), "проверяющий": источник,
             "файлы": {имя: хэш(байты) for имя, байты in sorted(файлы.items())}}
    записи = []
    полные_записи = []
    for имя, байты in файлы.items():
        if имя == "снимок.json":
            continue
        запись = проверяющий.разобрать_байты(байты)
        if not isinstance(запись, dict):
            raise ValueError("Запись не является объектом")
        if запись.get("схема") != "fum.test-run.v3":
            return {**общие, "состояние": "неподдержана", "схемаЗапусков": запись.get("схема", "отсутствует")}
        проверяющий.отчёты.проверить_запись(запись, имя, запрос)
        записи.append(запись)
        полные_записи.append((Path(имя), запись, байты))
    if not записи:
        raise ValueError("Нет записей проверок")
    записи.sort(key=lambda запись: запись["порядок"])
    полные_записи.sort(key=lambda запись: запись[1]["порядок"])
    for ключ in ("порядок", "идентификатор"):
        if len({запись[ключ] for запись in записи}) != len(записи):
            raise ValueError("Повторный порядок или UUID")
    общие["схемаЗапусков"] = "fum.test-run.v3"
    общие["запусков"] = len(записи)
    общие["коды"] = [запись["код_завершения"] for запись in записи]
    if any(запись["состояние"] != "завершён" for запись in записи):
        raise ValueError("Незавершённая приёмка")
    if "снимок.json" not in файлы:
        текст = байты_отчёта.decode("utf-8")
        начало, конец, маркер = проверяющий.отчёты.границы_управляемого_блока(текст)
        if маркер != проверяющий.отчёты.ОТКРЫТЫЙ_МАРКЕР:
            raise ValueError("Отсутствие снимка противоречит закрытому отчёту")
        связь = восстановить_отпечаток(чтение, коммит, сессия, корень_гит)
        if текст[начало:конец] != проверяющий.отчёты.сформировать_блок(полные_записи, маркер, связь["кандидат"]):
            raise ValueError("Открытый блок не соответствует точным запускам")
        return {**общие, "состояние": "checkpoint", "схемаОтчёта": "отсутствует"}
    снимок = проверяющий.разобрать_байты(файлы["снимок.json"])
    if not isinstance(снимок, dict):
        raise ValueError("Снимок не является объектом")
    общие["схемаОтчёта"] = снимок.get("схема", "отсутствует")
    if общие["схемаОтчёта"] != "fum.test-run-report.v2":
        return {**общие, "состояние": "неподдержана"}
    результат = проверяющий.проверить_байты_закрытого_отчёта(запрос, байты_отчёта, файлы)
    связь = восстановить_отпечаток(чтение, коммит, сессия, корень_гит)
    подтверждено = связь["кандидат"] == результат["отпечаток_закрытия"] == результат["отпечаток_запуска"]
    return {**общие, "состояние": "подтверждён" if подтверждено else "не подтверждён",
            "результатПроверки": результат["состояние"], "схемаПроверки": результат["схема"],
            "хэшСнимка": результат["sha256_снимка"], "финальныйЗапуск": результат["финальный_запуск"],
            "отпечатокЗакрытия": результат["отпечаток_закрытия"], "отпечатокЗапуска": результат["отпечаток_запуска"],
            "кандидат": связь["кандидат"], "хэшРазницы": связь["хэшРазницы"],
            "наборы": записи[-1]["профиль_проверки"]["полные_наборы"],
            "область": "точный сохранённый план проверок", "широкаяФункциональность": "не доказана"}


def собрать_интеграцию(чтение, источник, цель, запрос, корень_гит, репозиторий, задача, время):
    выбранное = {"стадия": "fuma", "ref": "refs/heads/fuma", "основание": "согласованный маршрут через fuma к master",
                 "источник": {"коммит": источник}, "цель": {"коммит": цель},
                 "квитанция": {"схема": "отсутствует"}, "отмена": {"схема": "отсутствует"},
                 "сохранность": {"схема": "отсутствует"}, "предыдущаяСтадия": {"стадия": "боковая"}}
    try:
        выбранное["источник"]["дерево"] = чтение.коммит(источник)["дерево"]
        выбранное["цель"]["дерево"] = чтение.коммит(цель)["дерево"]
        выбранное["доступность"] = "доступен"
    except (ValueError, OSError, subprocess.TimeoutExpired):
        выбранное["доступность"] = "недоступен"
    try:
        выбранное["ancestry"] = чтение.ancestry(источник, цель)
    except (ValueError, OSError, subprocess.TimeoutExpired):
        выбранное["ancestry"] = {"источник": источник, "цель": цель, "полнота": "неполная", "предок": "unknown"}
    try:
        выбранное["приёмка"] = извлечь_приёмку(чтение, источник, запрос, корень_гит)
    except (ValueError, OSError, subprocess.TimeoutExpired, проверяющий.ОшибкаОтчёта):
        выбранное["приёмка"] = {"коммит": источник, "состояние": "недоступна"}
    источники = {"поставка": dict(выбранное["источник"]), "цель": dict(выбранное["цель"]),
                 "проверяющий": источник_проверяющего(), "запрос": запрос,
                 "цели": {"fuma": copy.deepcopy(выбранное)},
                 "маршрут": {"схема": "fum.маршрут-интеграции.1", "основание": выбранное["основание"],
                             "коммитПостановки": "6ba824c69f09abb46cb5f356ce60e458cf99ecdd"}}
    return {"схема": "fum.структурированный-вход.2",
            "факты": {"репозиторий": репозиторий, "задача": задача, "время": время,
                       "исходнаяПоставка": источник, "цели": {"fuma": выбранное}}, "источники": источники,
            "прежнее": {"состояние": "нет", "причина": "", "область": "", "основания": {}},
            "обратнаяСвязь": {"рассмотрение": "не рассмотрено", "проверка": {}}}


def главный():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--корень-репозитория", required=True, type=Path)
    парсер.add_argument("--архив", type=Path)
    парсер.add_argument("--источник", required=True)
    парсер.add_argument("--цель", required=True)
    парсер.add_argument("--запрос", required=True)
    парсер.add_argument("--репозиторий", required=True)
    парсер.add_argument("--задача", required=True)
    парсер.add_argument("--время", required=True)
    параметры = парсер.parse_args()
    объекты = прочитать_архив(параметры.архив)["объекты"] if параметры.архив else None
    чтение = НаборОбъектов(объекты, корень=None if параметры.архив else параметры.корень_репозитория)
    результат = собрать_интеграцию(чтение, параметры.источник, параметры.цель, параметры.запрос,
                                   параметры.корень_репозитория, параметры.репозиторий, параметры.задача, параметры.время)
    print(json.dumps(результат, ensure_ascii=False, sort_keys=True, separators=(",", ":")))


if __name__ == "__main__":
    главный()

"""Три закреплённые поставки; сбор архива явный, воспроизведение автономное."""
import argparse
import json
from pathlib import Path

from интеграция_внимания import НаборОбъектов, собрать_интеграцию
from объекты_внимания import прочитать_архив, разобрать_архив


ПАКЕТ = Path(__file__).resolve().parents[1]
ЦЕЛЬ = "a728283474931eda71cd581ca5429121124ba3f6"
ПРИМЕРЫ = [
    ("c7cd5d33cbf44df0b714d76e188580e9b18d4473", "2026-09-11_13-05-09_MSK_принять-сравнение-декодирования"),
    ("8d89a695d6f099091a13d3ce60c924c7098105f2", "2026-09-11_13-30-58_MSK_подготовить-постановку-Windows-VM-на-macOS"),
    ("f49eeee3fd80a87cd63391d6606dafa19cd6d2b8", "2026-09-11_07-43-37_MSK_реализовать-интерпретатор-и-UTF-32"),
]


def главный():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--собрать-архив", type=Path)
    парсер.add_argument("--корень-репозитория", type=Path, default=ПАКЕТ.parents[1])
    параметры = парсер.parse_args()
    архив = ПАКЕТ / "Проверки/внимание/git-объекты.json"
    if параметры.собрать_архив:
        прежние = прочитать_архив(параметры.собрать_архив)["объекты"] if параметры.собрать_архив.exists() else None
        чтение = НаборОбъектов(прежние, корень=параметры.корень_репозитория)
    else:
        данные = прочитать_архив(архив)
        if данные.get("схема") != "fum.архив-объектов-внимания.1":
            raise ValueError("Неподдержанный архив")
        чтение = НаборОбъектов(данные["объекты"])
    результаты = [собрать_интеграцию(чтение, источник, ЦЕЛЬ, "Журнал/" + сессия + "/запрос.md",
                       параметры.корень_репозитория, "FUM", "фиксированные-примеры", "2026-09-11T18:00:00Z")
                  for источник, сессия in ПРИМЕРЫ]
    if параметры.собрать_архив:
        параметры.собрать_архив.parent.mkdir(parents=True, exist_ok=True)
        данные = {"схема": "fum.архив-объектов-внимания.1", "цель": ЦЕЛЬ, "примеры": ПРИМЕРЫ, "объекты": чтение.объекты}
        байты = (json.dumps(данные, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode()
        разобрать_архив(байты)
        параметры.собрать_архив.write_bytes(байты)
        print(json.dumps({"объектов": len(чтение.объекты), "байтов": параметры.собрать_архив.stat().st_size}, ensure_ascii=False))
    if not параметры.собрать_архив:
        for результат in результаты:
            print(json.dumps(результат, ensure_ascii=False, sort_keys=True, separators=(",", ":")))


if __name__ == "__main__":
    главный()

extension AutomationExecutor {
  public static func выполнить(
    _ определение: ОпределениеГрафа, вход: СтруктурированныйВход,
    параметры: ПараметрыЧувствительности, профиль: ((ЗамерИсполнения) -> Void)? = nil
  ) throws -> НаблюдениеГрафа {
    let начало = DispatchTime.now().uptimeNanoseconds
    guard Set(параметры.веса.keys) == Set(определение.сигналы.map(\.имя)) else {
      throw отказГрафа("Веса не совпадают с точным набором сигналов")
    }
    let корень = вход.представление
    let поля = try корень.объект(["схема", "факты", "источники", "прежнее", "обратнаяСвязь"])
    var значения = [String: УзелОпределения]()
    var трасса = [СледГрафа]()
    var времяТрассы: UInt64 = 0
    func истина(_ значение: УзелОпределения?) -> String {
      guard case .строка(let строка) = значение, ["да", "нет"].contains(строка) else {
        return "unknown"
      }
      return строка
    }
    func хэш(_ значение: УзелОпределения?) throws -> String {
      guard let значение else { return "отсутствует" }
      return sha256Digest(try каноническиеДанные(значение))
    }
    for шаг in определение.узлы {
      let аргументы = шаг.входы.map { $0.взять(корень, цель: определение.цель, значения: значения) }
      var выход: УзелОпределения?
      switch шаг.оператор {
      case "равно":
        if let а = аргументы[0], let б = аргументы[1] {
          выход = .строка(try каноническиеДанные(а) == каноническиеДанные(б) ? "да" : "нет")
        }
      case "содержит":
        if case .массив(let список) = аргументы[0], let искомое = аргументы[1] {
          let байты = try каноническиеДанные(искомое)
          выход = .строка(
            try список.contains { try каноническиеДанные($0) == байты } ? "да" : "нет")
        }
      case "все":
        let исходы = аргументы.map(истина)
        выход = .строка(
          исходы.contains("нет") ? "нет" : исходы.contains("unknown") ? "unknown" : "да")
      case "любой":
        let исходы = аргументы.map(истина)
        выход = .строка(
          исходы.contains("да") ? "да" : исходы.contains("unknown") ? "unknown" : "нет")
      case "не":
        let исход = истина(аргументы[0])
        выход = .строка(исход == "да" ? "нет" : исход == "нет" ? "да" : "unknown")
      case "хэш-значения":
        if let значение = аргументы[0] { выход = .строка(String(try хэш(значение).dropFirst(7))) }
      case "хэш-utf8":
        if case .строка(let текст) = аргументы[0] {
          выход = .строка(String(sha256Digest(Data(текст.utf8)).dropFirst(7)))
        }
      default: throw отказГрафа("Неподдержанная операция")
      }
      if let выход { значения[шаг.имя] = выход }
      let отметка = DispatchTime.now().uptimeNanoseconds
      трасса.append(
        СледГрафа(
          узел: шаг.имя, оператор: шаг.оператор, хэшиВходов: try аргументы.map(хэш),
          значение: (try? выход?.строка()) ?? "unknown", хэшВыхода: try хэш(выход)))
      времяТрассы += DispatchTime.now().uptimeNanoseconds - отметка
    }
    let обязательные = Dictionary(
      uniqueKeysWithValues: определение.обязательные.map { ($0, истина(значения[$0])) })
    var неизвестность = определение.обязательные.filter { обязательные[$0] != "да" }
    let частиОбласти = определение.идентичность.map {
      $0.взять(корень, цель: определение.цель, значения: [:])
    }
    let область: String
    if частиОбласти.contains(where: { $0 == nil }) {
      неизвестность.append("неполная идентичность")
      область = "unknown"
    } else {
      область = sha256Digest(
        try каноническиеДанные(УзелОпределения.массив(частиОбласти.compactMap { $0 })))
    }
    let прежнее = try поля["прежнее"]!.объект(["состояние", "причина", "область", "основания"])
    var состояние = try прежнее["состояние"]!.строка()
    var активнаяПричина = состояние == "активно" ? try прежнее["причина"]!.строка() : ""
    let прежниеОснования: [String: УзелОпределения]
    if case .объект(let словарь) = прежнее["основания"]! {
      прежниеОснования = словарь
    } else {
      throw отказГрафа("Неверные основания памяти")
    }
    var активныйКритерий =
      состояние == "активно" ? (try? прежниеОснования["критерий"]?.строка()) ?? "" : ""
    if состояние == "активно", активныйКритерий.isEmpty {
      неизвестность.append("неизвестный критерий прежней причины")
    }
    let прежняяОбласть = try прежнее["область"]!.строка()
    if состояние != "нет", прежняяОбласть != область {
      неизвестность.append("чужая область прежнего сигнала")
    }
    var выбранный: ИсходГрафа?
    if неизвестность.isEmpty {
      for исход in определение.исходы {
        let условие = истина(значения[исход.условие])
        if условие == "unknown" {
          неизвестность.append("условие исхода: " + исход.условие)
          break
        }
        if условие == "да" {
          выбранный = исход
          break
        }
      }
      if выбранный == nil, неизвестность.isEmpty { неизвестность.append("нет подходящего исхода") }
    }
    if let выбранный {
      switch выбранный.память {
      case "активировать":
        состояние = "активно"
        активнаяПричина = выбранный.причина
        активныйКритерий = выбранный.критерий
      case "устранить":
        состояние = "устранено"
        активнаяПричина = ""
        активныйКритерий = ""
      case "неприменимо":
        состояние = "неприменимо"
        активнаяПричина = ""
        активныйКритерий = ""
      default: break
      }
    }
    var память = поля["прежнее"]!
    if let выбранный, выбранный.память != "сохранить" || состояние == "нет" {
      var основания = [String: УзелОпределения]()
      for (имя, выбор) in определение.основания {

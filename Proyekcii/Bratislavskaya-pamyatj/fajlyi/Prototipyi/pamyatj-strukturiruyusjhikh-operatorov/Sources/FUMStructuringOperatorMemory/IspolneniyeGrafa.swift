public struct ОпределениеГрафа {
  fileprivate let представление: УзелОпределения
  public let идентификатор: String
  public let версия: Int
  public let цель: String
  fileprivate let идентичность: [ВыборГрафа]
  fileprivate let основания: [String: ВыборГрафа]
  fileprivate let узлы: [ШагГрафа]
  fileprivate let обязательные: [String]
  fileprivate let исходы: [ИсходГрафа]
  fileprivate let сигналы: [(имя: String, узел: String, роль: String)]

  public static func разобрать(_ данные: Data) throws -> Self {
    let корень = try разобратьГрафJSON(данные)
    let поля = try корень.объект([
      "схема", "идентификатор", "версия", "цель", "идентичность", "основания", "узлы",
      "обязательные", "исходы", "сигналы",
    ])
    guard try поля["схема"]!.строка() == "fum.определение-графа.2" else {
      throw отказГрафа("Неподдержанная схема графа")
    }
    let версия = try поля["версия"]!.целое()
    guard (1...1_000_000).contains(версия) else {
      throw отказГрафа("Неподдержанная версия определения")
    }
    let идентификатор = try непустаяСтрока(поля["идентификатор"]!)
    let цель = try непустаяСтрока(поля["цель"]!)
    var известные = Set<String>()
    var узлы = [ШагГрафа]()
    for запись in try поля["узлы"]!.массив() {
      let узел = try запись.объект(["идентификатор", "оператор", "входы"])
      let имя = try непустаяСтрока(узел["идентификатор"]!)
      let оператор = try непустаяСтрока(узел["оператор"]!)
      let входы = try узел["входы"]!.массив().map { try ВыборГрафа($0, известные: известные) }
      let число: ClosedRange<Int>
      switch оператор {
      case "равно", "содержит": число = 2...2
      case "не", "хэш-значения", "хэш-utf8": число = 1...1
      case "все", "любой": число = 1...32
      default: throw отказГрафа("Неизвестный общий оператор")
      }
      guard число.contains(входы.count), известные.insert(имя).inserted else {
        throw отказГрафа("Повтор узла либо неверное число входов")
      }
      узлы.append(ШагГрафа(имя: имя, оператор: оператор, входы: входы))
    }
    guard (1...256).contains(узлы.count) else { throw отказГрафа("Предел узлов графа") }
    func ссылка(_ узел: УзелОпределения) throws -> String {
      let имя = try непустаяСтрока(узел)
      guard известные.contains(имя) else { throw отказГрафа("Неизвестное условие") }
      return имя
    }
    let идентичность = try поля["идентичность"]!.массив().map { try ВыборГрафа($0, известные: []) }
    guard (1...8).contains(идентичность.count) else { throw отказГрафа("Предел идентичности") }
    guard case .объект(let поляОснований) = поля["основания"]!,
      (1...16).contains(поляОснований.count),
      поляОснований["критерий"] == nil
    else { throw отказГрафа("Неверный набор оснований памяти") }
    var основания = [String: ВыборГрафа]()
    for (имя, выбор) in поляОснований {
      основания[имя] = try ВыборГрафа(выбор, известные: известные)
    }
    let обязательные = try поля["обязательные"]!.массив().map(ссылка)
    guard !обязательные.isEmpty, Set(обязательные).count == обязательные.count else {
      throw отказГрафа("Нужны уникальные обязательные условия")
    }
    var исходы = [ИсходГрафа]()
    for запись in try поля["исходы"]!.массив() {
      let поля = try запись.объект([
        "условие", "результат", "память", "причина", "действие", "критерий",
      ])
      let память = try непустаяСтрока(поля["память"]!)
      guard ["активировать", "сохранить", "устранить", "неприменимо"].contains(память) else {
        throw отказГрафа("Неизвестный переход памяти")
      }
      исходы.append(
        ИсходГрафа(
          условие: try ссылка(поля["условие"]!), результат: try непустаяСтрока(поля["результат"]!),
          память: память, причина: try непустаяСтрока(поля["причина"]!),
          действие: try непустаяСтрока(поля["действие"]!),
          критерий: try непустаяСтрока(поля["критерий"]!)))
    }
    guard (1...32).contains(исходы.count) else { throw отказГрафа("Предел исходов") }
    let сигналы = try поля["сигналы"]!.массив().map { запись in
      let поля = try запись.объект(["идентификатор", "узел", "роль"])
      let роль = try поля["роль"]!.строка()
      guard ["обязательный-критерий", "чувствительность"].contains(роль) else {
        throw отказГрафа("Неизвестная роль сигнала")
      }
      return (
        имя: try непустаяСтрока(поля["идентификатор"]!), узел: try ссылка(поля["узел"]!), роль: роль
      )
    }
    guard (1...32).contains(сигналы.count), Set(сигналы.map(\.имя)).count == сигналы.count else {
      throw отказГрафа("Предел либо повтор сигналов")
    }
    return Self(
      представление: корень, идентификатор: идентификатор, версия: версия, цель: цель,
      идентичность: идентичность, основания: основания,
      узлы: узлы, обязательные: обязательные, исходы: исходы, сигналы: сигналы)
  }
}

public struct ПараметрыЧувствительности {
  public let версия: Int
  public let веса: [String: Int]
  public let порог: Int
  public let хэш: String

  public static func разобрать(_ данные: Data) throws -> Self {
    var поля = try разобратьГрафJSON(данные).объект(["схема", "версия", "веса", "порог", "хэш"])
    guard try поля["схема"]!.строка() == "fum.параметры-чувствительности.1",
      case .объект(let сырыеВеса) = поля["веса"]!
    else { throw отказГрафа("Неподдержанные параметры") }
    let версия = try поля["версия"]!.целое()
    let порог = try поля["порог"]!.целое()
    let хэш = try поля["хэш"]!.строка()
    guard (1...1_000_000).contains(версия), (0...10_000).contains(порог),
      (1...32).contains(сырыеВеса.count)
    else { throw отказГрафа("Параметры вне конечной области") }
    var веса = [String: Int]()
    for (имя, узел) in сырыеВеса {
      let вес = try узел.целое()
      guard (0...100).contains(вес) else { throw отказГрафа("Вес вне 0...100") }
      веса[имя] = вес
    }
    поля["хэш"] = .строка("")
    guard хэш == sha256Digest(try каноническиеДанные(УзелОпределения.объект(поля))) else {
      throw отказГрафа("Неверный хэш параметров")
    }
    return Self(версия: версия, веса: веса, порог: порог, хэш: хэш)
  }
}

public struct СтруктурированныйВход {
  fileprivate let представление: УзелОпределения
  public static func разобрать(_ данные: Data) throws -> Self {
    let корень = try разобратьГрафJSON(данные)
    let поля = try корень.объект(["схема", "факты", "источники", "прежнее", "обратнаяСвязь"])
    guard try поля["схема"]!.строка() == "fum.структурированный-вход.2",
      case .объект = поля["факты"]!, case .объект = поля["источники"]!
    else { throw отказГрафа("Неподдержанный структурированный вход") }
    let прежнее = try поля["прежнее"]!.объект(["состояние", "причина", "область", "основания"])
    let состояние = try прежнее["состояние"]!.строка()
    let причина = try прежнее["причина"]!.строка()
    let область = try прежнее["область"]!.строка()
    guard ["нет", "активно", "устранено", "неприменимо"].contains(состояние),
      case .объект = прежнее["основания"]!,
      состояние != "активно" || (!причина.isEmpty && !область.isEmpty)
    else { throw отказГрафа("Повреждена прежняя память") }
    let связь = try поля["обратнаяСвязь"]!.объект(["рассмотрение", "проверка"])
    guard ["не рассмотрено", "рассмотрено"].contains(try связь["рассмотрение"]!.строка()),
      case .объект = связь["проверка"]!
    else { throw отказГрафа("Повреждена обратная связь") }
    return Self(представление: корень)
  }
}


import Foundation

private func разобратьГрафJSON(_ данные: Data) throws -> УзелОпределения {
  var разбор = try РазборОпределения(данные)
  return try разбор.разобрать()
}

private func отказГрафа(_ пояснение: String) -> ОшибкаИсполнения {
  ОшибкаИсполнения("граф", пояснение)
}

private func непустаяСтрока(_ узел: УзелОпределения) throws -> String {
  let строка = try узел.строка()
  guard !строка.isEmpty, строка.utf8.count <= 512 else {
    throw отказГрафа("Недопустимая строка контракта")
  }
  return строка
}

private enum ВыборГрафа {
  case поле([String])
  case константа(УзелОпределения)
  case узел(String)
  case цель

  init(_ значение: УзелОпределения, известные: Set<String>) throws {
    guard case .объект(let поля) = значение, поля.count == 1, let (ключ, узел) = поля.first else {
      throw отказГрафа("Селектор содержит ровно одно поле")
    }
    switch ключ {
    case "поле":
      let путь = try узел.массив().map(непустаяСтрока)
      guard (1...12).contains(путь.count) else { throw отказГрафа("Путь селектора вне предела") }
      self = .поле(путь)
    case "константа": self = .константа(узел)
    case "узел":
      let имя = try непустаяСтрока(узел)
      guard известные.contains(имя) else {
        throw отказГрафа("Ссылка вперёд, цикл либо неизвестный узел")
      }
      self = .узел(имя)
    case "цель":
      guard try узел.строка() == "" else { throw отказГрафа("Неверный селектор цели") }
      self = .цель
    default: throw отказГрафа("Неизвестный селектор")
    }
  }

  func взять(_ вход: УзелОпределения, цель: String, значения: [String: УзелОпределения])
    -> УзелОпределения?
  {
    switch self {
    case .константа(let узел): return узел
    case .узел(let имя): return значения[имя]
    case .цель: return .строка(цель)
    case .поле(let путь):
      var текущий = вход
      for часть in путь {
        guard case .объект(let поля) = текущий,
          let следующий = поля[часть == "$цель" ? цель : часть]
        else { return nil }
        текущий = следующий
      }
      return текущий
    }
  }
}


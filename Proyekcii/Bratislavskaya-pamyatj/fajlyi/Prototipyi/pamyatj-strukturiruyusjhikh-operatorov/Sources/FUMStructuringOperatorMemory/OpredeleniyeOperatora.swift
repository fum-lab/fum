import Foundation

public enum ПорядокБайтов: String, Equatable, Sendable {
  case младшийПервым = "LE"
  case старшийПервым = "BE"
}

public enum ДействиеОператора: Equatable, Sendable {
  case обрезать
  case нижнийРегистр
  case сжатьПробелы
  case заменить(String, String)
  case префикс(String)
  case повторитьПравила([String])
  case упаковатьСлова(ширина: Int, порядок: ПорядокБайтов)

  var представление: (String, [String: УзелОпределения]) {
    switch self {
    case .обрезать: return ("обрезать", [:])
    case .нижнийРегистр: return ("нижний-регистр", [:])
    case .сжатьПробелы: return ("сжать-пробелы", [:])
    case .заменить(let старое, let новое):
      return ("заменить", ["старое": .строка(старое), "новое": .строка(новое)])
    case .префикс(let текст): return ("префикс", ["текст": .строка(текст)])
    case .повторитьПравила(let правила):
      return ("повторить-правила", ["правила": .массив(правила.map { .строка($0) })])
    case .упаковатьСлова(let ширина, let порядок):
      return ("упаковать-слова", ["ширина": .целое(ширина), "порядок": .строка(порядок.rawValue)])
    }
  }
}

public struct ШагОператора: Equatable, Sendable {
  public let идентификатор: String
  public let действие: ДействиеОператора

  public init(идентификатор: String, действие: ДействиеОператора) {
    self.идентификатор = идентификатор
    self.действие = действие
  }

  var представление: УзелОпределения {
    let (оператор, аргументы) = действие.представление
    return .объект([
      "идентификатор": .строка(идентификатор),
      "оператор": .строка(оператор), "аргументы": .объект(аргументы),
    ])
  }

  static func разобрать(_ узел: УзелОпределения) throws -> ШагОператора {
    let поля = try узел.объект(["идентификатор", "оператор", "аргументы"])
    let имя = try поля["оператор"]!.строка()
    let аргументы = поля["аргументы"]!
    let действие: ДействиеОператора
    switch имя {
    case "обрезать", "нижний-регистр", "сжать-пробелы":
      _ = try аргументы.объект([])
      действие =
        имя == "обрезать" ? .обрезать : (имя == "нижний-регистр" ? .нижнийРегистр : .сжатьПробелы)
    case "заменить":
      let значения = try аргументы.объект(["старое", "новое"])
      действие = .заменить(try значения["старое"]!.строка(), try значения["новое"]!.строка())
    case "префикс":
      let значения = try аргументы.объект(["текст"])
      действие = .префикс(try значения["текст"]!.строка())
    case "повторить-правила":
      let значения = try аргументы.объект(["правила"])
      действие = .повторитьПравила(try значения["правила"]!.массив().map { try $0.строка() })
    case "упаковать-слова":
      let значения = try аргументы.объект(["ширина", "порядок"])
      guard let порядок = ПорядокБайтов(rawValue: try значения["порядок"]!.строка()) else {
        throw ОшибкаИсполнения("схема", "Нужен явный порядок LE или BE")
      }
      действие = .упаковатьСлова(ширина: try значения["ширина"]!.целое(), порядок: порядок)
    default: throw ОшибкаИсполнения("схема", "Неизвестный общий оператор")
    }
    return ШагОператора(идентификатор: try поля["идентификатор"]!.строка(), действие: действие)
  }
}

public struct ДиапазонБайта: Equatable, Sendable {
  public let от: Int
  public let до: Int

  public init(от: Int, до: Int) {
    self.от = от
    self.до = до
  }
  func содержит(_ значение: Int) -> Bool { от <= значение && значение <= до }
  var представление: УзелОпределения { .объект(["от": .целое(от), "до": .целое(до)]) }
}

public struct БитовоеПоле: Equatable, Sendable {
  public let байт: Int
  public let маска: Int
  public let сдвиг: Int

  public init(байт: Int, маска: Int, сдвиг: Int) {
    self.байт = байт
    self.маска = маска
    self.сдвиг = сдвиг
  }
  var представление: УзелОпределения {
    .объект(["байт": .целое(байт), "маска": .целое(маска), "сдвиг": .целое(сдвиг)])
  }
}

public struct ПравилоБайтов: Equatable, Sendable {
  public let идентификатор: String
  public let байты: [ДиапазонБайта]
  public let поля: [БитовоеПоле]

  public init(идентификатор: String, байты: [ДиапазонБайта], поля: [БитовоеПоле]) {
    self.идентификатор = идентификатор
    self.байты = байты
    self.поля = поля
  }
  var представление: УзелОпределения {
    .объект([
      "идентификатор": .строка(идентификатор),
      "байты": .массив(байты.map(\.представление)), "поля": .массив(поля.map(\.представление)),
    ])
  }
  static func разобрать(_ узел: УзелОпределения) throws -> ПравилоБайтов {
    let значения = try узел.объект(["идентификатор", "байты", "поля"])
    let байты = try значения["байты"]!.массив().map { узел in
      let диапазон = try узел.объект(["от", "до"])
      return ДиапазонБайта(от: try диапазон["от"]!.целое(), до: try диапазон["до"]!.целое())
    }
    let поля = try значения["поля"]!.массив().map { узел in
      let поле = try узел.объект(["байт", "маска", "сдвиг"])
      return БитовоеПоле(
        байт: try поле["байт"]!.целое(), маска: try поле["маска"]!.целое(),
        сдвиг: try поле["сдвиг"]!.целое())
    }
    return ПравилоБайтов(
      идентификатор: try значения["идентификатор"]!.строка(), байты: байты, поля: поля)
  }
}

public struct ОпределениеОператора: Equatable, Sendable {
  public let идентификатор: String
  public let версия: Int
  public let правила: [ПравилоБайтов]
  public let шаги: [ШагОператора]

  public init(
    идентификатор: String, версия: Int, правила: [ПравилоБайтов] = [], шаги: [ШагОператора]
  ) {
    self.идентификатор = идентификатор
    self.версия = версия
    self.правила = правила
    self.шаги = шаги
  }

  var представление: УзелОпределения {
    .объект([
      "схема": .строка("fum.определение-оператора.1"),
      "идентификатор": .строка(идентификатор), "версия": .целое(версия),
      "правила": .массив(правила.map(\.представление)), "шаги": .массив(шаги.map(\.представление)),
    ])
  }

  public func данные() throws -> Data {
    try проверить()
    return try каноническиеДанные(представление)
  }

  public static func разобрать(_ данные: Data) throws -> ОпределениеОператора {
    var разбор = try РазборОпределения(данные)
    let поля = try разбор.разобрать().объект([
      "схема", "идентификатор", "версия", "правила", "шаги",
    ])
    guard try поля["схема"]!.строка() == "fum.определение-оператора.1" else {
      throw ОшибкаИсполнения("схема", "Неподдержанная версия схемы определения")
    }
    let определение = ОпределениеОператора(
      идентификатор: try поля["идентификатор"]!.строка(),
      версия: try поля["версия"]!.целое(),
      правила: try поля["правила"]!.массив().map(ПравилоБайтов.разобрать),
      шаги: try поля["шаги"]!.массив().map(ШагОператора.разобрать))
    try определение.проверить()
    return определение
  }

  func проверить() throws {
    func потребовать(_ условие: Bool, _ причина: String) throws {
      guard условие else { throw ОшибкаИсполнения("определение", причина) }
    }
    func имя(_ значение: String) -> Bool {
      !значение.isEmpty && значение.utf8.count <= 128
        && значение.unicodeScalars.allSatisfy { !CharacterSet.controlCharacters.contains($0) }
    }
    try потребовать(имя(идентификатор) && (1...1_000_000).contains(версия), "Неверная идентичность")
    try потребовать(шаги.count <= 32 && правила.count <= 32, "Превышен предел шагов или правил")
    try потребовать(
      Set(шаги.map(\.идентификатор)).count == шаги.count
        && Set(правила.map(\.идентификатор)).count == правила.count, "Повтор идентификатора")
    for правило in правила {
      try потребовать(
        имя(правило.идентификатор) && (1...8).contains(правило.байты.count)
          && (1...8).contains(правило.поля.count), "Неверное правило или отсутствие продвижения")
      for диапазон in правило.байты {
        try потребовать(
          (0...255).contains(диапазон.от) && диапазон.до >= диапазон.от
            && диапазон.до <= 255, "Неверный диапазон байта")
      }
      var занятыеБиты: UInt64 = 0
      for поле in правило.поля {
        try потребовать(
          (0..<правило.байты.count).contains(поле.байт)
            && (1...255).contains(поле.маска) && (0...31).contains(поле.сдвиг),
          "Неверное битовое поле")
        let биты = UInt64(поле.маска) << поле.сдвиг
        try потребовать(
          биты <= UInt32.max && биты & занятыеБиты == 0, "Переполнение или перекрытие полей")
        занятыеБиты |= биты
      }
    }
    for шаг in шаги {
      try потребовать(имя(шаг.идентификатор), "Неверное имя шага")
      switch шаг.действие {
      case .заменить(let старое, let новое):
        try потребовать(
          !старое.isEmpty && старое.utf8.count <= 4096 && новое.utf8.count <= 4096,
          "Неверный аргумент замены")
      case .префикс(let текст):
        try потребовать(текст.utf8.count <= 4096, "Превышен размер префикса")
      case .упаковатьСлова(let ширина, _):
        try потребовать([1, 2, 4].contains(ширина), "Неверная ширина слова")
      case .повторитьПравила(let имена):
        try потребовать(
          !имена.isEmpty && имена.count <= 32 && Set(имена).count == имена.count,
          "Неверная композиция правил")
        let выбранные = имена.compactMap { имя in правила.first { $0.идентификатор == имя } }
        try потребовать(выбранные.count == имена.count, "Неизвестное имя правила")
        for номер in выбранные.indices {
          for другое in выбранные.indices where другое < номер {
            let совместимы = zip(выбранные[номер].байты, выбранные[другое].байты).allSatisfy {
              max($0.от, $1.от) <= min($0.до, $1.до)
            }
            try потребовать(!совместимы, "Неоднозначные или префиксные правила")
          }
        }
      case .обрезать, .нижнийРегистр, .сжатьПробелы: break
      }
    }
    try потребовать(
      каноническиеДанные(представление).count <= 65_536, "Превышен размер определения")
  }
}

public enum РесурсыОпределений {
  public static func прочитать(_ имя: String) throws -> Data {
    guard ["UTF-8-в-UTF-32LE", "нормализация"].contains(имя),
      let адрес = Bundle.module.url(
        forResource: имя, withExtension: "json", subdirectory: "Определения")
    else { throw ОшибкаИсполнения("ресурс", "Нет сохранённого определения") }
    return try КонечныйВвод.определение(адрес.path)
  }
}

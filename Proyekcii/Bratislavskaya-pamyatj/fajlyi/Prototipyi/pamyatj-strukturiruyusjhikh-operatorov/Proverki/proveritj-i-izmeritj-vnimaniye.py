"""Сквозное исполнение открытых графов, A/B и монотонный профиль одного бинарника."""
import argparse
import hashlib
import json
import platform
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path


ПАКЕТ = Path(__file__).resolve().parents[1]
ФИКСТУРЫ = ПАКЕТ / "Проверки/внимание"
ОПРЕДЕЛЕНИЯ = ПАКЕТ / "Sources/FUMStructuringOperatorMemory/Определения"


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def канон(объект):
    return json.dumps(объект, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()


def исполнить(бинарник, определение, параметры, вход, профиль=False):
    команда = [str(бинарник), "внимание", "--определение", str(определение), "--параметры", str(параметры)]
    if профиль:
        команда.append("--профиль")
    начало = time.perf_counter_ns()
    исход = subprocess.run(команда, input=вход, capture_output=True, timeout=15)
    длительность = time.perf_counter_ns() - начало
    assert исход.returncode == 0, исход.stderr.decode()
    return json.loads(исход.stdout), исход.stdout, исход.stderr, длительность


def главный():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--бинарник", required=True, type=Path)
    парсер.add_argument("--выход", required=True, type=Path)
    аргументы = парсер.parse_args()
    бинарник = аргументы.бинарник.resolve(strict=True)
    случаи = json.loads((ФИКСТУРЫ / "случаи.json").read_bytes())["случаи"]
    for случай in случаи:
        имя = случай["определение"]
        исход, _, _, _ = исполнить(бинарник, ОПРЕДЕЛЕНИЯ / (имя + ".json"),
            ФИКСТУРЫ / (имя + "-обычные.json"), (ФИКСТУРЫ / (случай["вход"] + ".json")).read_bytes())
        assert исход["результат"] == случай["результат"], случай["вход"]
        assert исход["состояние"] == случай["состояние"], случай["вход"]
        assert исход["полномочие"] == "не предоставлено"
    замеры = []
    sys.path.insert(0, str(ПАКЕТ / "Сборщики"))
    from примеры_интеграции import ПРИМЕРЫ, ЦЕЛЬ
    from интеграция_внимания import собрать_интеграцию
    from объекты_внимания import НаборОбъектов, прочитать_архив
    from факты_внимания import собрать_readme, проверить_ссылку
    начало = time.perf_counter_ns()
    архив = прочитать_архив(ФИКСТУРЫ / "git-объекты.json")
    разбор_архива = time.perf_counter_ns() - начало
    чтение = НаборОбъектов(архив["объекты"])
    реальные = []
    for (источник, сессия), ожидаемый in zip(ПРИМЕРЫ, ["требуется-интеграция", "разобрать-приёмку", "unknown"], strict=True):
        начало = time.perf_counter_ns()
        факты = собрать_интеграцию(чтение, источник, ЦЕЛЬ, "Журнал/" + сессия + "/запрос.md",
            ПАКЕТ.parents[1], "FUM", "фиксированные-примеры", "2026-09-11T18:00:00Z")
        сбор = time.perf_counter_ns() - начало
        байты = канон(факты)
        наблюдение, вывод, _, длительность = исполнить(бинарник,
            ОПРЕДЕЛЕНИЯ / "потребность-интеграции.json", ФИКСТУРЫ / "потребность-интеграции-обычные.json", байты)
        assert наблюдение["результат"] == ожидаемый, (источник, наблюдение["результат"], наблюдение["неизвестность"])
        выбранное = факты["факты"]["цели"]["fuma"]
        реальные.append({"источник": источник, "цель": ЦЕЛЬ, "вход_sha256": хэш(байты),
            "наблюдение_sha256": хэш(вывод), "результат": наблюдение["результат"],
            "ancestry": выбранное["ancestry"], "приёмка": выбранное["приёмка"],
            "сбор_наносекунды": сбор, "исполнение_процесс_наносекунды": длительность})
    with tempfile.TemporaryDirectory(prefix="fum-внимание-профиль-") as каталог:
        каталог = Path(каталог)
        копия = каталог / "копия"
        for имя in ("Приложения/FUMA/README.md", "Документация/README.md"):
            файл = копия / имя
            файл.parent.mkdir(parents=True, exist_ok=True)
            файл.write_bytes((ПАКЕТ.parents[1] / имя).read_bytes())
        память = None
        цикл = []
        for шаг, пример, рассмотрение, проверять, ожидаемый in [
            ("наблюдение", "README-без-ссылки", "не рассмотрено", False, "расхождение"),
            ("рассмотрение", "README-без-ссылки", "рассмотрено", False, "расхождение"),
            ("изменение", "README-со-ссылкой", "рассмотрено", False, "проверить-результат"),
            ("проверка", "README-со-ссылкой", "рассмотрено", True, "resolved"),
        ]:
            источник = json.loads((ФИКСТУРЫ / (пример + ".json")).read_bytes())["источники"]["README.md"]["текст"]
            (копия / "README.md").write_bytes(источник.encode())
            начало = time.perf_counter_ns()
            вход = собрать_readme(копия, "открытая-копия-FUM", "фиксированный-цикл", "2026-09-11T18:00:00Z",
                память, {"рассмотрение": рассмотрение, "проверка": {}})
            сбор = time.perf_counter_ns() - начало
            начало = time.perf_counter_ns()
            if проверять:
                свидетельство = проверить_ссылку(вход, "Приложения/FUMA/README.md")
                вход["обратнаяСвязь"]["проверка"] = свидетельство
                вход["источники"]["проверка"] = свидетельство
            проверка = time.perf_counter_ns() - начало
            результат, байты, _, длительность = исполнить(бинарник, ОПРЕДЕЛЕНИЯ / "актуальность-README.json",
                ФИКСТУРЫ / "актуальность-README-обычные.json", канон(вход))
            assert результат["результат"] == ожидаемый, (шаг, результат["результат"], результат["неизвестность"])
            память = результат["память"]
            цикл.append({"шаг": шаг, "результат": результат["результат"], "память": память,
                "рассмотрение": результат["рассмотрение"], "вход_sha256": хэш(канон(вход)),
                "наблюдение_sha256": хэш(байты), "сбор_наносекунды": сбор,
                "проверка_наносекунды": проверка, "исполнение_процесс_наносекунды": длительность})
        for имя, пример, цель in [("актуальность-README", "README-без-ссылки", "Документация/README.md"),
                                  ("потребность-интеграции", "интеграция-проверенная", "master")]:
            определение = ОПРЕДЕЛЕНИЯ / (имя + ".json")
            вход = (ФИКСТУРЫ / (пример + ".json")).read_bytes()
            параметры = ФИКСТУРЫ / (имя + "-обычные.json")
            а, _, _, _ = исполнить(бинарник, определение, параметры, вход)
            другой = json.loads(определение.read_bytes())
            другой["цель"] = цель
            путь = каталог / (имя + ".json")
            путь.write_bytes(канон(другой))
            б, _, _, _ = исполнить(бинарник, путь, параметры, вход)
            assert а["результат"] != б["результат"] and а["хэшОпределения"] != б["хэшОпределения"] and а["трасса"] != б["трасса"]
            пониженные = ФИКСТУРЫ / (имя + "-пониженные.json")
            б, _, _, _ = исполнить(бинарник, определение, пониженные, вход)
            assert а["результат"] == б["результат"] and а["хэшОпределения"] == б["хэшОпределения"]
            assert а["хэшПараметров"] != б["хэшПараметров"] and а["внимание"] != б["внимание"] and а["трасса"] != б["трасса"]
            повторы = []
            эталон = None
            for номер in range(3):
                результат, байты, поток, длительность = исполнить(бинарник, определение, параметры, вход, True)
                assert эталон is None or байты == эталон
                эталон = байты
                стадии = [json.loads(строка) for строка in поток.splitlines()]
                assert [з["стадия"] for з in стадии] == ["загрузка", "разбор", "граф", "трасса"]
                assert all(з["исход"] == "успешно" and type(з["наносекунды"]) is int and з["наносекунды"] >= 0 for з in стадии)
                повторы.append({"номер": номер + 1, "процесс_наносекунды": длительность, "стадии": стадии})
            замеры.append({"определение": имя, "байтов_входа": len(вход), "байтов_наблюдения": len(эталон),
                "вход_sha256": хэш(вход), "определение_sha256": хэш(определение.read_bytes()), "параметры_sha256": хэш(параметры.read_bytes()),
                "наблюдение_sha256": хэш(эталон), "повторы": повторы,
                "медианы_наносекунды": {стадия: int(statistics.median(з["стадии"][н]["наносекунды"] for з in повторы)) for н, стадия in enumerate(["загрузка", "разбор", "граф", "трасса"])}})
        # Явный отказ, включая отсутствие параметров, повтор аргумента и неверную схему.
        плохие = каталог / "неверные-параметры.json"
        плохие.write_bytes(b"{}")
        for хвост, вход in [([], b"{}"), (["--параметры", str(плохие)], b"{}"),
                            (["--параметры", str(параметры), "--параметры", str(параметры)], b"{}"),
                            (["--параметры", str(параметры)], b"a" * 65537)]:
            исход = subprocess.run([str(бинарник), "внимание", "--определение", str(определение), *хвост], input=вход, capture_output=True, timeout=15)
            assert исход.returncode != 0 and not исход.stdout
    файлы = list((ПАКЕТ / "Sources").rglob("*.swift")) + list((ПАКЕТ / "Сборщики").glob("*.py"))
    отчёт = {"схема": "fum.профиль-внимания.1", "бинарник_sha256": хэш(бинарник.read_bytes()),
        "сценарий_sha256": хэш(Path(__file__).read_bytes()), "исходники_sha256": {п.relative_to(ПАКЕТ).as_posix(): хэш(п.read_bytes()) for п in sorted(файлы)},
        "Python": platform.python_version(), "платформа": platform.system(), "архитектура": platform.machine(),
        "случаев": len(случаи), "A_B": "оба определения и оба набора чувствительности", "замеры": замеры,
        "реальные_примеры": реальные, "разбор_архива_наносекунды": разбор_архива,
        "цикл_README": цикл,
        "архив_sha256": хэш((ФИКСТУРЫ / "git-объекты.json").read_bytes()),
        "граница": "Один заранее собранный бинарник. Сборка исключена; процесс включает запуск и stdout. Загрузка, разбор, граф и трасса измерены отдельно. Кэш ОС не очищается; повторы показаны в исходном порядке."}
    аргументы.выход.write_text(json.dumps(отчёт, ensure_ascii=False, sort_keys=True, indent=2) + "\n")
    print(json.dumps({"сценариев": len(случаи), "медианы": {з["определение"]: з["медианы_наносекунды"] for з in замеры}}, ensure_ascii=False))


if __name__ == "__main__":
    главный()

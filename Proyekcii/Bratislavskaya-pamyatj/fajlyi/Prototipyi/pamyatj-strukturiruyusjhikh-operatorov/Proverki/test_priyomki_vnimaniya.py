"""Фиксированные реальные поставки воспроизводятся без их локальных Git-объектов."""
import importlib.util
import json
import sys
import unittest
from unittest.mock import patch
from pathlib import Path


class ПроверкиПриёмки(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        класс.пакет = Path(__file__).resolve().parents[1]
        путь = класс.пакет / "Сборщики/интеграция_внимания.py"
        описание = importlib.util.spec_from_file_location("интеграция_внимания", путь)
        класс.модуль = importlib.util.module_from_spec(описание)
        sys.modules[описание.name] = класс.модуль
        описание.loader.exec_module(класс.модуль)

    def test_три_реальные_поставки_из_переносимого_архива(сам):
        архив = json.loads((сам.пакет / "Проверки/внимание/git-объекты.json").read_bytes())
        цель = "a728283474931eda71cd581ca5429121124ba3f6"
        случаи = [
            ("c7cd5d33cbf44df0b714d76e188580e9b18d4473", "2026-09-11_13-05-09_MSK_принять-сравнение-декодирования", "нет", "подтверждён"),
            ("8d89a695d6f099091a13d3ce60c924c7098105f2", "2026-09-11_13-30-58_MSK_подготовить-постановку-Windows-VM-на-macOS", "нет", "checkpoint"),
            ("f49eeee3fd80a87cd63391d6606dafa19cd6d2b8", "2026-09-11_07-43-37_MSK_реализовать-интерпретатор-и-UTF-32", "да", "не подтверждён"),
        ]
        for источник, сессия, предок, приёмка in случаи:
            чтение = сам.модуль.НаборОбъектов(архив["объекты"])
            факты = сам.модуль.собрать_интеграцию(чтение, источник, цель, "Журнал/" + сессия + "/запрос.md",
                                                   сам.пакет.parents[1], "fum-lab/fum", "одна-задача", "2026-09-11T18:00:00Z")
            выбранное = факты["факты"]["цели"]["fuma"]
            сам.assertEqual(выбранное["ancestry"]["предок"], предок)
            сам.assertEqual(выбранное["приёмка"]["состояние"], приёмка)
            сам.assertEqual(выбранное["источник"]["коммит"], источник)
            сам.assertNotIn("нужноИнтегрировать", str(факты))
            if приёмка == "не подтверждён":
                сам.assertEqual(выбранное["приёмка"]["результатПроверки"], "проверен")
                сам.assertNotEqual(выбранное["приёмка"]["кандидат"], выбранное["приёмка"]["отпечатокЗакрытия"])
            if приёмка == "подтверждён":
                сам.assertEqual(выбранное["приёмка"]["кандидат"], выбранное["приёмка"]["отпечатокЗакрытия"])
                сам.assertEqual(выбранное["приёмка"]["схемаОтчёта"], "fum.test-run-report.v2")

    def test_недоступный_источник_остаётся_неизвестным(сам):
        факты = сам.модуль.собрать_интеграцию(сам.модуль.НаборОбъектов({}), "a" * 40, "b" * 40,
                "Журнал/2026-09-11_12-00-00_MSK_проверить-фикстуру/запрос.md", сам.пакет.parents[1],
                "открытая-фикстура", "одна-задача", "2026-09-11T18:00:00Z")
        сам.assertEqual(факты["факты"]["цели"]["fuma"]["доступность"], "недоступен")

    def test_снятый_снимок_и_необъект_не_становятся_checkpoint(сам):
        архив = json.loads((сам.пакет / "Проверки/внимание/git-объекты.json").read_bytes())
        чтение = сам.модуль.НаборОбъектов(архив["объекты"])
        коммит = "c7cd5d33cbf44df0b714d76e188580e9b18d4473"
        запрос = "Журнал/2026-09-11_13-05-09_MSK_принять-сравнение-декодирования/запрос.md"
        файлы = чтение.файлы_каталога(коммит, str(Path(запрос).parent) + "/материалы/запуски-проверок")
        del файлы["снимок.json"]
        with patch.object(чтение, "файлы_каталога", return_value=файлы):
            факты = сам.модуль.собрать_интеграцию(чтение, коммит, "a728283474931eda71cd581ca5429121124ba3f6", запрос, сам.пакет.parents[1], "FUM", "з", "в")
        сам.assertEqual(факты["факты"]["цели"]["fuma"]["приёмка"]["состояние"], "недоступна")
        файлы[next(iter(файлы))] = b"[]"
        with patch.object(чтение, "файлы_каталога", return_value=файлы):
            факты = сам.модуль.собрать_интеграцию(чтение, коммит, "a728283474931eda71cd581ca5429121124ba3f6", запрос, сам.пакет.parents[1], "FUM", "з", "в")
        сам.assertEqual(факты["факты"]["цели"]["fuma"]["приёмка"]["состояние"], "недоступна")


if __name__ == "__main__":
    unittest.main()

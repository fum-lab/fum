"""Межпроцессное восстановление проверяется фактическими Git-фикстурами."""
from pathlib import Path
import tempfile
import unittest
from фикстуры import создать, снимок_данных, снимок_репозиториев, процесс, перенос


class ПроверкиПереноса(unittest.TestCase):
    def test_первое_восстановление_после_перемещения_новым_процессом(сам):
        with tempfile.TemporaryDirectory() as временный:
            основание = Path(временный).resolve()
            привязки = создать(основание)
            источник = Path(привязки['источник'])
            назначение = Path(привязки['назначение'])
            данные = снимок_данных(источник)
            репозитории = снимок_репозиториев(источник)
            идентичность = источник.stat().st_ino
            путь_плана = основание/'план.json'
            путь_привязок = основание/'привязки.json'
            путь_плана.write_bytes(перенос.канон.кодировать(перенос.построить(привязки)))
            путь_привязок.write_bytes(перенос.канон.кодировать(привязки))
            первый = процесс(путь_плана,путь_привязок,'после-перемещения')
            сам.assertEqual(77,первый.returncode,первый.stderr.decode())
            сам.assertFalse(источник.exists())
            сам.assertEqual(идентичность,назначение.stat().st_ino)
            сам.assertEqual(данные,снимок_данных(назначение))
            повтор = процесс(путь_плана,путь_привязок)
            сам.assertEqual(0,повтор.returncode,повтор.stderr.decode())
            сам.assertEqual(данные,снимок_данных(назначение))
            сам.assertEqual(репозитории,снимок_репозиториев(назначение))
            сам.assertEqual(идентичность,назначение.stat().st_ino)
            ещё = процесс(путь_плана,путь_привязок)
            сам.assertEqual(0,ещё.returncode,ещё.stderr.decode())
            сам.assertEqual(повтор.stdout,ещё.stdout)

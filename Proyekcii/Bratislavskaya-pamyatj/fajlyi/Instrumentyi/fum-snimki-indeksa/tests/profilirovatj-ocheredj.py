"""Повторяемый профиль частной очереди: raw-байты, доставка, ack, WAL и барьер."""
import argparse
import json
import os
import platform
import tempfile
import tracemalloc
import uuid
from pathlib import Path
from time import perf_counter_ns
from unittest import mock

from test_очередь import Очередь, ЗАДАЧА, СНИМОК, сообщение, строка_события
from канон import кодировать, хэш
from диалог import экспортировать


def выполнить():
    разбор = argparse.ArgumentParser()
    разбор.add_argument('--размеры', default='2,100')
    разбор.add_argument('--выход', required=True, type=Path)
    разбор.add_argument('--сравнить', type=Path)
    параметры = разбор.parse_args()
    корень_инструмента = Path(__file__).resolve().parents[1]
    исходники = {п.relative_to(корень_инструмента).as_posix(): хэш(п.read_bytes()) for п in sorted(корень_инструмента.rglob('*.py'))}
    замеры = []
    настоящий = os.fsync
    for размер in map(int, параметры.размеры.split(',')):
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный).resolve()
            источник = корень / 'диалог.jsonl'
            начало = строка_события('session_meta', {'id': ЗАДАЧА}) + сообщение('user', 'начать')
            источник.write_bytes(начало)
            _, курсор = экспортировать(начало, ЗАДАЧА)
            решения = []
            def связь(запрос): return {'запрос': запрос, 'состояние': 'доступен', 'решения': решения}
            интервалы = {}
            синхронизации = 0
            время_синхронизаций = 0
            def синхронизировать(дескриптор):
                nonlocal синхронизации, время_синхронизаций
                старт = perf_counter_ns()
                try: return настоящий(дескриптор)
                finally:
                    синхронизации += 1
                    время_синхронизаций += perf_counter_ns() - старт
            def измерить(имя, действие):
                старт = perf_counter_ns()
                try: return действие()
                finally: интервалы[имя] = интервалы.get(имя, 0) + perf_counter_ns() - старт
            tracemalloc.start()
            with mock.patch('очередь.os.fsync', side_effect=синхронизировать):
                очередь = измерить('создание', lambda: Очередь.создать(корень / 'очередь', источник, ЗАДАЧА, СНИМОК, 'a' * 64, курсор, ['читать', 'писать']))
                хвост = сообщение('user', 'одинаковые байты') * размер
                with источник.open('ab') as поток: поток.write(хвост)
                измерить('сохранение_хвоста', lambda: очередь.барьер(связь))
                выход = []
                for номер in range(размер):
                    доставка = измерить('доставка', lambda: очередь.доставить(связь))
                    ссылка = доставка['ссылка']
                    выход.append({'номер': ссылка['номер'], 'начало': ссылка['начало'], 'конец': ссылка['конец'], 'сырая_строка': доставка['сырая_строка'], 'происхождение': доставка['происхождение']})
                    решения[:] = [{'идентификатор': str(uuid.UUID(int=номер + 1)), 'ссылка': ссылка, 'действие': 'учесть', 'разрешения': None}]
                    измерить('решение_и_подтверждение', lambda: очередь.подтвердить(ссылка, связь))
                барьер = измерить('барьер', lambda: очередь.барьер(связь))['барьер']
                assert барьер is not None
                новая = Очередь(очередь.каталог, очередь.привязка)
                итог = измерить('переоткрытие_и_сверка', lambda: новая.проверить_барьер(барьер, связь))
                assert итог['совпадает'] and not итог['исполнение_разрешено']
                _, пик = tracemalloc.get_traced_memory()
                tracemalloc.stop()
            замеры.append({'сообщений': размер, 'байты_источника': len(начало + хвост), 'байты_журнала': (очередь.каталог / 'события.jsonl').stat().st_size,
                           'хэш_источника': хэш(начало + хвост), 'хэш_доставленных_байтов': хэш(кодировать(выход)),
                           'поколение': итог['поколение'], 'разрешения': итог['разрешения'], 'интервалы_наносекунды': интервалы,
                           'синхронизации': синхронизации, 'синхронизации_наносекунды': время_синхронизаций, 'пик_памяти_python_байты': пик})
    if параметры.сравнить:
        прежние = json.loads(параметры.сравнить.read_text())['замеры']
        for до, после in zip(прежние, замеры, strict=True):
            for поле in ('сообщений', 'байты_источника', 'хэш_источника', 'хэш_доставленных_байтов', 'поколение', 'разрешения', 'синхронизации'):
                assert до[поле] == после[поле], поле
    assert исходники == {п.relative_to(корень_инструмента).as_posix(): хэш(п.read_bytes()) for п in sorted(корень_инструмента.rglob('*.py'))}, 'исходники изменились во время профиля'
    результат = {'схема': 'fum.профиль-очереди.1', 'python': platform.python_version(), 'платформа': platform.platform(),
                 'условия': 'monotonic wall-clock с tracemalloc; fsync вложены в стадии и не складываются с ними; Python heap не равен RSS; живой runtime заменён явным синтетическим callback; точные raw-байты и нормализованные ссылки без локальных UUID/путей сверяются отдельно; измеряются точные варианты реализации; сравнение этого сценария не обещает общего ускорения',
                 'версии_файлов': исходники, 'замеры': замеры}
    параметры.выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + '\n')
    for замер in замеры: print(замер['сообщений'], 'сообщений,', round(sum(замер['интервалы_наносекунды'].values()) / 1e9, 3), 'с,', замер['синхронизации'], 'fsync')


if __name__ == '__main__': выполнить()

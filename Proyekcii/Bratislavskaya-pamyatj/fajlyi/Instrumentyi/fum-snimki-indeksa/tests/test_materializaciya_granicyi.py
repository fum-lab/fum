    def test_остановка_процесса_до_закрытия_не_даёт_квитанции(сам):
        параметры = сам.параметры()
        for номер, граница in enumerate(('маркер', 'файл', 'квитанция', 'установка')):
            другие = {**параметры, 'назначение': сам.папка / ('target-c' + str(номер)), 'квитанция': сам.папка / ('receipt-c' + str(номер))}
            потомок = os.fork()
            if потомок == 0:
                исходный = материализация._создать_файл
                установка = os.link
                def остановить(родитель, имя, байты, режим, профиль):
                    результат = исходный(родитель, имя, байты, режим, профиль)
                    if ((граница == 'маркер' and имя.endswith('.незавершено')) or
                        (граница == 'файл' and имя == 'данные-00000.txt') or
                        (граница == 'квитанция' and имя.endswith('.подготовка'))): os._exit(91)
                    return результат
                def установить(*аргументы, **именованные):
                    результат = установка(*аргументы, **именованные)
                    if граница == 'установка': os._exit(91)
                    return результат
                with patch.object(материализация, '_создать_файл', side_effect=остановить), patch.object(материализация.os, 'link', side_effect=установить):
                    try: материализация.материализовать(**другие)
                    except BaseException: os._exit(92)
                    os._exit(93)
            _, исход = os.waitpid(потомок, 0)
            сам.assertEqual(os.waitstatus_to_exitcode(исход), 91)
            with сам.assertRaises((ОшибкаВхода, OSError)): материализация.проверить_материализацию(**другие)


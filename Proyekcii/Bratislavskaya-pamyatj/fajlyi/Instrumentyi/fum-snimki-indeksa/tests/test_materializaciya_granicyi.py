    def test_отказы_второго_блока_и_квитанции(сам):
        (сам.корень / 'большой').write_bytes(b'A' * (2 * 1024 * 1024 + 1))
        гит(сам.корень, 'add', 'большой'); обновить(сам.корень, сам.вход)
        параметры = сам.параметры(); создать_файл = материализация._создать_файл; запись = os.write
        for номер, (место, вид) in enumerate((('большой', 'коротко'), ('большой', 'полон'), ('квитанция', 'коротко'), ('квитанция', 'полон'))):
            другие = {**параметры, 'назначение': сам.папка / ('target-b' + str(номер)), 'квитанция': сам.папка / ('receipt-b' + str(номер))}
            def создать_с_отказом(родитель, имя, байты, режим, профиль):
                if имя == место or (место == 'квитанция' and имя.endswith('.подготовка')):
                    счётчик = 0
                    def записать(дескриптор, блок):
                        nonlocal счётчик
                        счётчик += 1
                        if место == 'квитанция' or счётчик == 2:
                            if вид == 'полон': raise OSError(28, 'synthetic ENOSPC')
                            return запись(дескриптор, блок[:len(блок)//2])
                        return запись(дескриптор, блок)
                    with patch.object(материализация.os, 'write', side_effect=записать):
                        return создать_файл(родитель, имя, байты, режим, профиль)
                return создать_файл(родитель, имя, байты, режим, профиль)
            with сам.subTest(место=место, вид=вид), patch.object(материализация, '_создать_файл', side_effect=создать_с_отказом), сам.assertRaises((ОшибкаВхода, OSError)):
                материализация.материализовать(**другие)
            сам.assertFalse(другие['квитанция'].exists())


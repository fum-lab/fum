import copy
import json
import os
import sys
from pathlib import Path
from unittest import mock

import unittest
import test_очередь as основа
from test_очередь import Очередь, ОшибкаВхода, сообщение, строка_события, ЗАДАЧА, СНИМОК


class ГраницыОчереди(unittest.TestCase):
    setUp = основа.ПоздняяОчередь.setUp
    связь = основа.ПоздняяОчередь.связь
    дописать = основа.ПоздняяОчередь.дописать
    решение = основа.ПоздняяОчередь.решение

    def test_дописанное_при_подтверждении_канала_видно_барьеру(сам):
        старый = сам.очередь.барьер(сам.связь)['барьер']
        def связь(запрос):
            сам.дописать(сообщение('user', 'поздняя команда'))
            return сам.связь(запрос)
        сам.assertFalse(сам.очередь.проверить_барьер(старый, связь)['совпадает'])

    def test_повреждённая_оболочка_сообщения_не_пропускается(сам):
        сам.дописать(строка_события('response_item', []))
        сам.assertEqual(сам.очередь.барьер(сам.связь)['состояние'], 'неоднозначно')

    def test_курсор_подменён_до_создания(сам):
        курсор = copy.deepcopy(сам.курсор)
        курсор['позиции'][0]['начало'] += 1
        with сам.assertRaises(ОшибкаВхода):
            Очередь.создать(сам.корень / 'чужая', сам.источник, ЗАДАЧА, СНИМОК, 'a' * 64, курсор, [])
        сам.assertFalse((сам.корень / 'чужая').exists())

    def test_чужая_ссылка_и_повтор_идентификатора_решения(сам):
        сам.дописать(сообщение('user', 'уточнение'))
        доставка = сам.очередь.доставить(сам.связь)
        решение = сам.решение(доставка)
        сам.очередь.подтвердить(доставка['ссылка'], сам.связь)
        решение['действие'] = 'отозвать'
        сам.assertEqual(сам.очередь.барьер(сам.связь)['состояние'], 'неоднозначно')

    def test_составное_сообщение_сохраняется_без_досклейки(сам):
        сам.дописать(строка_события('response_item', {'type': 'message', 'role': 'user',
            'content': [{'type': 'input_text', 'text': 'ограничить'}, {'type': 'input_image', 'image_url': 'data:image/png;base64,AA=='}],
            'internal_chat_message_metadata_passthrough': {'content_item_kinds': ['user.text', 'user.image']}}))
        доставка = сам.очередь.доставить(сам.связь)
        сам.assertEqual(доставка['происхождение'], 'человек')
        сам.assertEqual(len(json.loads(bytes.fromhex(доставка['сырая_строка']))['payload']['content']), 2)

    def test_неоднозначное_происхождение_не_разблокируется(сам):
        сам.дописать(строка_события('response_item', {'type': 'message', 'role': 'user', 'content': [{'type': 'input_text', 'text': 'остановись'}]}))
        доставка = сам.очередь.доставить(сам.связь)
        сам.assertEqual(доставка['происхождение'], 'неоднозначный')
        сам.очередь.подтвердить(доставка['ссылка'], сам.связь)
        сам.assertIsNone(сам.очередь.барьер(сам.связь)['барьер'])

    def test_квитанция_старого_вызова_канала_отклоняется(сам):
        ответ = сам.связь('00000000-0000-4000-8000-000000000009')
        сам.assertEqual(сам.очередь.барьер(lambda _: ответ)['состояние'], 'канал утрачен')

    def test_подмена_именованного_журнала_при_вызове_канала(сам):
        старый = сам.очередь.барьер(сам.связь)['барьер']
        def связь(запрос):
            путь = сам.корень / 'очередь' / 'события.jsonl'
            копия = путь.read_bytes()
            путь.unlink(); путь.write_bytes(копия); путь.chmod(0o600)
            return сам.связь(запрос)
        with сам.assertRaises(ОшибкаВхода): сам.очередь.проверить_барьер(старый, связь)

    def test_отказ_каждой_синхронизации_сохраняет_запрет_после_переоткрытия(сам):
        настоящий = os.fsync
        for номер in range(1, 5):
            with сам.subTest(номер=номер):
                сам.очередь = Очередь.создать(сам.корень / ('отказ' + str(номер)), сам.источник, ЗАДАЧА, СНИМОК, 'a' * 64, сам.курсор, [])
                старый = сам.очередь.барьер(сам.связь)['барьер']
                сам.дописать(сообщение('user', str(номер)))
                счётчик = 0
                def отказ(дескриптор):
                    nonlocal счётчик
                    счётчик += 1
                    if счётчик == номер: raise OSError('синтетический отказ синхронизации')
                    return настоящий(дескриптор)
                with mock.patch('очередь.os.fsync', side_effect=отказ), сам.assertRaises(OSError): сам.очередь.барьер(сам.связь)
                новая = Очередь(сам.очередь.каталог, сам.очередь.привязка)
                сам.assertFalse(новая.проверить_барьер(старый, сам.связь)['совпадает'])
                сам.assertIsNone(новая.барьер(сам.связь)['барьер'])
                сам.источник.write_bytes(сам.начало)

    def test_авария_процесса_до_и_после_записи_события(сам):
        for номер in range(1, 5):
            with сам.subTest(номер=номер):
                очередь = Очередь.создать(сам.корень / ('авария' + str(номер)), сам.источник, ЗАДАЧА, СНИМОК, 'a' * 64, сам.курсор, [])
                старый = очередь.барьер(сам.связь)['барьер']
                сам.дописать(сообщение('user', str(номер)))
                ребёнок = os.fork()
                if ребёнок == 0:
                    настоящий = os.fsync
                    счётчик = 0
                    def авария(дескриптор):
                        nonlocal счётчик
                        счётчик += 1
                        настоящий(дескриптор)
                        if счётчик == номер: os._exit(73)
                    with mock.patch('очередь.os.fsync', side_effect=авария): очередь.барьер(сам.связь)
                    os._exit(74)
                _, статус = os.waitpid(ребёнок, 0)
                сам.assertEqual(os.waitstatus_to_exitcode(статус), 73)
                сам.assertFalse(очередь.проверить_барьер(старый, сам.связь)['совпадает'])
                сам.источник.write_bytes(сам.начало)

    def test_нулевая_и_короткая_запись(сам):
        сам.дописать(сообщение('user', 'дописать'))
        настоящая = os.write
        with mock.patch('очередь.os.write', side_effect=lambda дескриптор, байты: настоящая(дескриптор, байты[:3])):
            сам.assertIsNotNone(сам.очередь.доставить(сам.связь))
        сам.дописать(сообщение('user', 'ещё'))
        with mock.patch('очередь.os.write', return_value=0), сам.assertRaises(ОшибкаВхода): сам.очередь.барьер(сам.связь)
        сам.assertIsNone(сам.очередь.барьер(сам.связь)['барьер'])

    def test_создание_сохраняет_уже_наблюдённый_хвост(сам):
        сам.дописать(сообщение('user', 'отмена до создания')[:-1])
        другая = Очередь.создать(сам.корень / 'другая', сам.источник, ЗАДАЧА, СНИМОК, 'a' * 64, сам.курсор, [])
        сам.источник.write_bytes(сам.начало)
        сам.assertIsNone(другая.барьер(сам.связь)['барьер'])

    def test_решение_одной_очереди_не_применяется_к_другой(сам):
        другая = Очередь.создать(сам.корень / 'другая', сам.источник, ЗАДАЧА, СНИМОК, 'b' * 64, сам.курсор, [])
        сам.дописать(сообщение('user', 'уточнение'))
        первая = сам.очередь.доставить(сам.связь)
        вторая = другая.доставить(сам.связь)
        сам.решение(первая)
        сам.assertEqual(другая.барьер(сам.связь)['состояние'], 'неоднозначно')
        сам.assertNotEqual(первая['ссылка'], вторая['ссылка'])
        with сам.assertRaises(ОшибкаВхода): другая.подтвердить(вторая['ссылка'], сам.связь)

    def test_нет_типа_полезного_сообщения_и_специальные_числа(сам):
        сам.дописать(строка_события('response_item', {'role': 'user', 'content': []}))
        сам.assertEqual(сам.очередь.барьер(сам.связь)['состояние'], 'неоднозначно')
        сам.источник.write_bytes(сам.начало)
        другая = Очередь.создать(сам.корень / 'числа', сам.источник, ЗАДАЧА, СНИМОК, 'b' * 64, сам.курсор, [])
        сам.дописать(b'{"type":"event_msg","payload":{"value":NaN}}\n')
        сам.assertIsNone(другая.барьер(сам.связь)['барьер'])

    def test_чужая_аварийная_метка_не_удаляется(сам):
        сам.дописать(сообщение('user', 'сохранить'))
        настоящий = os.fsync
        счётчик = 0
        def подменить(дескриптор):
            nonlocal счётчик
            счётчик += 1
            настоящий(дескриптор)
            if счётчик == 3:
                метка = сам.очередь.каталог / 'pending'
                метка.rename(сам.корень / 'прежняя-метка')
                метка.write_bytes(b'foreign'); метка.chmod(0o600)
        with mock.patch('очередь.os.fsync', side_effect=подменить), сам.assertRaises(ОшибкаВхода): сам.очередь.барьер(сам.связь)
        сам.assertEqual((сам.очередь.каталог / 'pending').read_bytes(), b'foreign')

    def test_нет_места_в_середине_записи_события(сам):
        сам.дописать(сообщение('user', 'сохранить'))
        настоящая = os.write
        счётчик = 0
        def отказ(дескриптор, байты):
            nonlocal счётчик
            счётчик += 1
            if счётчик == 2: return настоящая(дескриптор, байты[:12])
            if счётчик == 3: raise OSError(28, 'нет места')
            return настоящая(дескриптор, байты)
        with mock.patch('очередь.os.write', side_effect=отказ), сам.assertRaises(OSError): сам.очередь.барьер(сам.связь)
        сам.assertIsNone(сам.очередь.барьер(сам.связь)['барьер'])

    def test_изменённый_полный_журнал_и_логический_номер(сам):
        путь = сам.очередь.каталог / 'события.jsonl'
        байты = путь.read_bytes()
        путь.write_bytes(байты.replace('"поколение":1'.encode(), '"поколение":true'.encode()))
        сам.assertIsNone(сам.очередь.барьер(сам.связь)['барьер'])

    def test_появление_метки_при_чистом_наблюдении(сам):
        старый = сам.очередь.барьер(сам.связь)['барьер']
        def связь(запрос):
            (сам.очередь.каталог / 'pending').write_bytes(b'unknown')
            return сам.связь(запрос)
        with сам.assertRaises(ОшибкаВхода): сам.очередь.проверить_барьер(старый, связь)

"""Частная долговечная очередь raw JSONL и наблюдаемый барьер; не исполнитель."""
import copy
import fcntl
import json
import os
import stat
import uuid
from contextlib import contextmanager
from pathlib import Path

from канон import ОшибкаВхода, _пары, _запрет_числа, кодировать, прочитать, требовать, поля, идентификатор, число, хэш, хэш_строка
from диалог import экспортировать
from происхождение_сообщений import классифицировать_сообщение

ПРЕДЕЛ_ИСТОЧНИКА = 64 * 1024 * 1024
ПРЕДЕЛ_ЖУРНАЛА = 256 * 1024 * 1024


def _набор(значение):
    требовать(type(значение) is list and all(type(часть) is str and часть for часть in значение), 'неверные разрешения')
    требовать(значение == sorted(set(значение)), 'набор должен быть упорядочен без повторов')
    return значение


def _файл(дескриптор, режим=None):
    данные = os.fstat(дескриптор)
    требовать(stat.S_ISREG(данные.st_mode) and данные.st_nlink == 1 and данные.st_uid == os.getuid(), 'не частный обычный файл')
    if режим is not None: требовать(stat.S_IMODE(данные.st_mode) == режим, 'неверный режим файла')
    return данные


def _чтение(дескриптор, предел):
    данные = bytearray()
    while True:
        часть = os.read(дескриптор, min(1024 * 1024, предел + 1 - len(данные)))
        if not часть: return bytes(данные)
        данные.extend(часть)
        требовать(len(данные) <= предел, 'превышен предел байтов')


def _запись(дескриптор, данные):
    while данные:
        длина = os.write(дескриптор, данные)
        требовать(длина > 0, 'нулевая запись')
        данные = данные[длина:]


def _источник(путь):
    требовать(путь == путь.resolve(), 'symlink в источнике')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        до = _файл(дескриптор)
        данные = _чтение(дескриптор, ПРЕДЕЛ_ИСТОЧНИКА)
        после = os.fstat(дескриптор)
        имя = путь.stat(follow_symlinks=False)
        признаки = lambda запись: (запись.st_dev, запись.st_ino, запись.st_size, запись.st_mtime_ns, запись.st_ctime_ns)
        требовать(признаки(до) == признаки(после) == признаки(имя), 'источник изменился при чтении')
        return данные, [до.st_dev, до.st_ino]
    finally: os.close(дескриптор)


def _разобрать_хвост(состояние):
    данные = состояние['сырой_источник']
    граница = данные.rfind(b'\n') + 1
    позиции = []
    начало = состояние['начало']['курсор']['граница_байтов']
    try:
        for строка in (часть + b'\n' for часть in данные[начало:граница].split(b'\n')[:-1]):
            # Только LF разделяет JSONL, другие управляющие байты — повреждение.
            требовать(строка.endswith(b'\n'), 'строка не закончена LF')
            запись = json.loads(строка.decode('utf-8'), object_pairs_hook=_пары, parse_constant=_запрет_числа)
            требовать(type(запись) is dict and запись.get('type') != 'session_meta', 'повторная идентичность источника')
            полезное = запись.get('payload')
            требовать(type(запись.get('type')) is str and type(полезное) is dict, 'повреждённая оболочка raw-записи')
            if запись['type'] == 'response_item': требовать(type(полезное.get('type')) is str, 'нет типа response_item')
            if запись.get('type') == 'response_item' and type(полезное) is dict and полезное.get('type') == 'message':
                требовать(полезное.get('role') in ('user', 'assistant', 'system', 'developer', 'tool'), 'неизвестная роль')
                if полезное['role'] == 'user':
                    происхождение = классифицировать_сообщение(полезное)
                    ссылка = {'задача': состояние['начало']['задача'], 'источник': состояние['начало']['курсор']['хэш_источника'],
                              'очередь': состояние['начало']['очередь'], 'снимок': состояние['начало']['снимок'], 'хэш_входа': состояние['начало']['хэш_входа'],
                              'номер': len(позиции) + 1, 'начало': начало, 'конец': начало + len(строка), 'хэш': хэш(строка)}
                    позиции.append({'ссылка': ссылка, 'сырая_строка': строка.hex(), 'происхождение': происхождение})
                    if происхождение == 'неоднозначный': состояние['блокировка'] = 'неоднозначно'
            начало += len(строка)
    except (ValueError, UnicodeError, RecursionError):
        состояние['блокировка'] = 'неоднозначно'
    состояние['сообщения'] = позиции
    состояние['курсор'] = {'граница_байтов': граница, 'хэш_префикса': хэш(данные[:граница]), 'наблюдённые_байты': len(данные), 'хэш_наблюдения': хэш(данные)}
    состояние['частичный'] = граница != len(данные)


def _найти(состояние, ссылка):
    требовать(type(ссылка) is dict, 'неверная ссылка')
    номер = число(ссылка.get('номер'))
    требовать(1 <= номер <= len(состояние['сообщения']), 'номер вне очереди')
    сообщение = состояние['сообщения'][номер - 1]
    требовать(кодировать(ссылка) == кодировать(сообщение['ссылка']), 'ссылка не соответствует сохранённой raw-строке')
    return сообщение


def _применить(состояние, событие):
    вид = событие['вид']
    данные = событие['данные']
    if вид == 'источник':
        поля(данные, ('байты',))
        добавка = bytes.fromhex(данные['байты'])
        требовать(добавка and добавка.hex() == данные['байты'], 'неверные raw-байты')
        состояние['сырой_источник'] += добавка
        требовать(len(состояние['сырой_источник']) <= ПРЕДЕЛ_ИСТОЧНИКА, 'слишком большой источник')
        _разобрать_хвост(состояние)
    elif вид == 'блокировка':
        требовать(данные in ('канал утрачен', 'неоднозначно'), 'неверная блокировка')
        состояние['блокировка'] = данные
    elif вид == 'доставка':
        запись = _найти(состояние, данные)
        требовать(запись['ссылка']['номер'] == состояние['подтверждено'] + 1 and состояние['доставлено'] == состояние['подтверждено'], 'нарушен порядок доставки')
        состояние['доставлено'] += 1
    elif вид == 'подтверждение':
        запись = _найти(состояние, данные)
        номер = запись['ссылка']['номер']
        требовать(номер == состояние['подтверждено'] + 1 == состояние['доставлено'], 'нарушен порядок подтверждения')
        требовать(запись['происхождение'] != 'человек' or номер in состояние['обработано'], 'человеческая команда ещё не обработана')
        состояние['подтверждено'] = номер
    elif вид == 'решение':
        поля(данные, ('идентификатор', 'ссылка', 'действие', 'разрешения'))
        идентификатор(данные['идентификатор'])
        требовать(данные['идентификатор'] not in состояние['решения'], 'повтор решения в журнале')
        запись = _найти(состояние, данные['ссылка'])
        сырая = json.loads(bytes.fromhex(запись['сырая_строка']).decode('utf-8'), object_pairs_hook=_пары, parse_constant=_запрет_числа)
        требовать(классифицировать_сообщение(сырая['payload']) == 'человек', 'решение не имеет человеческого raw-происхождения')
        действие = данные['действие']
        требовать(действие in ('учесть', 'отозвать', 'сузить'), 'неизвестное типизированное решение')
        if действие == 'сузить':
            новые = _набор(данные['разрешения'])
            требовать(set(новые) <= set(состояние['разрешения']), 'расширение полномочий запрещено')
            состояние['разрешения'] = новые
        else: требовать(данные['разрешения'] is None, 'неожиданные разрешения')
        if действие == 'отозвать': состояние['отменено'] = True
        состояние['решения'][данные['идентификатор']] = данные
        состояние['обработано'].add(запись['ссылка']['номер'])
    else: raise ОшибкаВхода('неизвестный вид события')


class Очередь:
    def __init__(сам, каталог, привязка):
        сам.каталог = Path(каталог).absolute()
        сам.привязка = copy.deepcopy(привязка)

    @classmethod
    def создать(класс, каталог, источник, задача, снимок, хэш_входа, курсор, разрешения):
        идентификатор(задача); идентификатор(снимок); хэш_строка(хэш_входа)
        источник = Path(источник).absolute()
        сырые_байты, узел = _источник(источник)
        _, сверенный = экспортировать(сырые_байты, задача, квитанция=курсор, закрепить=True)
        разрешения = sorted(разрешения)
        _набор(разрешения)
        привязка = {'схема': 'fum.очередь-поздних-команд.1', 'очередь': str(uuid.uuid4()), 'задача': задача, 'снимок': снимок,
                    'хэш_входа': хэш_входа, 'курсор': сверенный, 'путь_источника': str(источник), 'узел_источника': узел}
        очередь = класс(каталог, привязка)
        родитель = очередь.каталог.parent
        требовать(родитель == родитель.resolve() and stat.S_IMODE(родитель.stat().st_mode) == 0o700 and родитель.stat().st_uid == os.getuid(), 'нужен частный физический родитель 0700')
        очередь.каталог.mkdir(mode=0o700)
        for имя in ('замок', 'события.jsonl'):
            дескриптор = os.open(очередь.каталог / имя, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
            os.fsync(дескриптор); os.close(дескриптор)
        родитель_фд = os.open(родитель, os.O_RDONLY | os.O_DIRECTORY)
        try: os.fsync(родитель_фд)
        finally: os.close(родитель_фд)
        начало = {'привязка': привязка, 'байты': сырые_байты.hex(), 'разрешения': разрешения}
        with очередь._доступ(начать=True) as (каталог_фд, журнал, состояние):
            очередь._дописать(каталог_фд, журнал, состояние, 'начало', начало)
        return очередь

    @contextmanager
    def _доступ(сам, начать=False):
        требовать(сам.каталог == сам.каталог.resolve(), 'symlink каталога очереди')
        каталог = os.open(сам.каталог, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        замок = журнал = None
        try:
            признаки = os.fstat(каталог)
            требовать(stat.S_IMODE(признаки.st_mode) == 0o700 and признаки.st_uid == os.getuid(), 'каталог должен быть частным 0700')
            замок = os.open('замок', os.O_RDWR | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=каталог)
            _файл(замок, 0o600)
            fcntl.flock(замок, fcntl.LOCK_EX)
            журнал = os.open('события.jsonl', os.O_RDWR | os.O_APPEND | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=каталог)
            _файл(журнал, 0o600)
            требовать(set(os.listdir(каталог)) <= {'замок', 'события.jsonl', 'pending'}, 'лишний файл очереди')
            байты = _чтение(журнал, ПРЕДЕЛ_ЖУРНАЛА)
            состояние = None
            if 'pending' not in os.listdir(каталог):
                if начать:
                    требовать(not байты, 'очередь уже начата')
                    состояние = {'поколение': 0, 'хэш': '0' * 64}
                else:
                    try: состояние = сам._воспроизвести(байты)
                    except (ValueError, KeyError, TypeError, RecursionError): состояние = None
            # Несовпадение внешней привязки не маскируется повреждением журнала.
            if состояние and not начать: требовать(кодировать(состояние['начало']) == кодировать(сам.привязка), 'чужая привязка очереди')
            if состояние is not None: состояние['ожидаемые_байты_журнала'] = байты
            def проверить_имена():
                требовать(сам.каталог == сам.каталог.resolve(), 'путь очереди подменён')
                текущие = os.fstat(каталог)
                требовать(stat.S_IMODE(текущие.st_mode) == 0o700 and текущие.st_uid == os.getuid(), 'режим каталога изменился')
                требовать(set(os.listdir(каталог)) <= {'замок', 'события.jsonl', 'pending'}, 'инвентарь очереди изменился')
                for открытый, именованный in ((os.fstat(каталог), сам.каталог.stat(follow_symlinks=False)),
                    (_файл(замок, 0o600), os.stat('замок', dir_fd=каталог, follow_symlinks=False)),
                    (_файл(журнал, 0o600), os.stat('события.jsonl', dir_fd=каталог, follow_symlinks=False))):
                    требовать((открытый.st_dev, открытый.st_ino) == (именованный.st_dev, именованный.st_ino), 'именованный inode очереди подменён')
            проверить_имена()
            yield каталог, журнал, состояние
            проверить_имена()
            if состояние is not None:
                требовать(set(os.listdir(каталог)) == {'замок', 'события.jsonl'}, 'появилась аварийная метка')
            if состояние and not начать:
                требовать(кодировать(состояние['начало']) == кодировать(сам.привязка), 'привязка изменена во время операции')
                os.lseek(журнал, 0, os.SEEK_SET)
                требовать(_чтение(журнал, ПРЕДЕЛ_ЖУРНАЛА) == состояние['ожидаемые_байты_журнала'], 'журнал изменился при операции')
                проверить_имена()
                требовать(set(os.listdir(каталог)) == {'замок', 'события.jsonl'}, 'появилась аварийная метка после чтения')
        finally:
            if журнал is not None: os.close(журнал)
            if замок is not None: os.close(замок)
            os.close(каталог)

    def _воспроизвести(сам, байты):
        требовать(байты and байты.endswith(b'\n'), 'оборванный журнал')
        состояние = {'поколение': 0, 'хэш': '0' * 64}
        for строка in байты.split(b'\n')[:-1]:
            сырая = строка + b'\n'
            событие = прочитать(сырая)
            поля(событие, ('поколение', 'предыдущий_хэш', 'вид', 'данные'))
            требовать(число(событие['поколение']) == состояние['поколение'] + 1 and событие['предыдущий_хэш'] == состояние['хэш'], 'цепочка поколений повреждена')
            if состояние['поколение'] == 0:
                требовать(событие['вид'] == 'начало', 'нет начального события')
                данные = событие['данные']
                поля(данные, ('привязка', 'байты', 'разрешения'))
                привязка = данные['привязка']
                сырые_байты = bytes.fromhex(данные['байты'])
                экспортировать(сырые_байты, привязка['задача'], квитанция=привязка['курсор'], закрепить=True)
                требовать(привязка['курсор']['граница_байтов'] <= len(сырые_байты) <= ПРЕДЕЛ_ИСТОЧНИКА, 'недопустимый начальный хвост')
                состояние.update({'начало': привязка, 'сырой_источник': сырые_байты, 'разрешения': _набор(данные['разрешения']), 'блокировка': None,
                                  'отменено': False, 'сообщения': [], 'доставлено': 0, 'подтверждено': 0, 'обработано': set(), 'решения': {}})
                _разобрать_хвост(состояние)
            else: _применить(состояние, событие)
            состояние.update(поколение=событие['поколение'], хэш=хэш(сырая))
        return состояние

    def _дописать(сам, каталог, журнал, состояние, вид, данные):
        событие = {'поколение': состояние['поколение'] + 1, 'предыдущий_хэш': состояние['хэш'], 'вид': вид, 'данные': данные}
        байты = кодировать(событие)
        требовать(os.fstat(журнал).st_size + len(байты) <= ПРЕДЕЛ_ЖУРНАЛА, 'журнал заполнен')
        метка = os.open('pending', os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=каталог)
        try:
            _запись(метка, кодировать({'поколение': событие['поколение'], 'хэш': хэш(байты)}))
            os.fsync(метка)
            своя_метка = os.fstat(метка)
        finally: os.close(метка)
        os.fsync(каталог)
        try:
            _запись(журнал, байты)
            os.fsync(журнал)
            именованная = os.stat('pending', dir_fd=каталог, follow_symlinks=False)
            требовать((своя_метка.st_dev, своя_метка.st_ino) == (именованная.st_dev, именованная.st_ino), 'подмена аварийной метки')
            os.unlink('pending', dir_fd=каталог)
            os.fsync(каталог)
        except BaseException:
            # Ошибка удаления/последнего fsync не превращается в успешный вызов.
            try:
                метка = os.open('pending', os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=каталог)
                os.fsync(метка); os.close(метка); os.fsync(каталог)
            except OSError: pass
            raise
        состояние['ожидаемые_байты_журнала'] += байты
        if вид != 'начало':
            _применить(состояние, событие)
            состояние.update(поколение=событие['поколение'], хэш=хэш(байты))

    def _обновить(сам, каталог, журнал, состояние, наблюдать):
        if состояние is None or наблюдать is None: return False
        def событие(вид, данные): сам._дописать(каталог, журнал, состояние, вид, данные)
        def прочитать_канал():
            try:
                сырые_байты, узел = _источник(Path(состояние['начало']['путь_источника']))
            except OSError:
                if состояние['блокировка'] is None: событие('блокировка', 'канал утрачен')
                return False
            except ОшибкаВхода:
                if состояние['блокировка'] is None: событие('блокировка', 'неоднозначно')
                return False
            if узел != состояние['начало']['узел_источника'] or not сырые_байты.startswith(состояние['сырой_источник']):
                if состояние['блокировка'] is None: событие('блокировка', 'неоднозначно')
                return False
            if len(сырые_байты) > len(состояние['сырой_источник']): событие('источник', {'байты': сырые_байты[len(состояние['сырой_источник']):].hex()})
            return True
        if not прочитать_канал(): return False
        try:
            запрос = str(uuid.uuid4())
            ответ = наблюдать(запрос)
            поля(ответ, ('запрос', 'состояние', 'решения'))
            требовать(ответ['запрос'] == запрос and ответ['состояние'] == 'доступен' and type(ответ['решения']) is list, 'нет свежего подтверждения связи')
        except Exception:
            if состояние['блокировка'] is None: событие('блокировка', 'канал утрачен')
            return False
        if not прочитать_канал(): return False
        for решение in ответ['решения']:
            try:
                прежнее = состояние['решения'].get(решение.get('идентификатор'))
                if прежнее is not None:
                    требовать(кодировать(прежнее) == кодировать(решение), 'подмена решения с тем же UUID')
                    continue
                _применить(copy.deepcopy(состояние), {'вид': 'решение', 'данные': решение})
            except (ValueError, KeyError, TypeError, AttributeError):
                if состояние['блокировка'] is None: событие('блокировка', 'неоднозначно')
                return False
            событие('решение', решение)
        return True

    def _итог(сам, состояние, свежий=False):
        if состояние is None:
            return {'состояние': 'неоднозначно', 'барьер': None, 'поколение': None, 'разрешения': [], 'исполнение_разрешено': False}
        статус = состояние['блокировка']
        if статус is None:
            if состояние['отменено']: статус = 'отменено'
            elif not свежий or состояние['частичный'] or состояние['подтверждено'] != len(состояние['сообщения']): статус = 'неоднозначно'
            else: статус = 'можно рассматривать следующий шаг'
        барьер = None
        if статус == 'можно рассматривать следующий шаг':
            барьер = {'схема': 'fum.барьер-поздних-команд.1', 'привязка': сам.привязка, 'поколение': состояние['поколение'],
                      'хэш_поколения': состояние['хэш'], 'курсор': состояние['курсор'], 'подтверждено': состояние['подтверждено'], 'разрешения': состояние['разрешения']}
        return {'состояние': статус, 'барьер': copy.deepcopy(барьер), 'поколение': состояние['поколение'],
                'разрешения': list(состояние['разрешения']), 'исполнение_разрешено': False}

    def состояние(сам):
        """Только хранимые сведения; без свежего канала барьер не выдаётся."""
        with сам._доступ() as (_, __, состояние): return сам._итог(состояние)

    def барьер(сам, наблюдать):
        with сам._доступ() as (каталог, журнал, состояние):
            свежий = сам._обновить(каталог, журнал, состояние, наблюдать)
            return сам._итог(состояние, свежий)

    def проверить_барьер(сам, барьер, наблюдать):
        with сам._доступ() as (каталог, журнал, состояние):
            свежий = сам._обновить(каталог, журнал, состояние, наблюдать)
            итог = сам._итог(состояние, свежий)
            итог['совпадает'] = итог['барьер'] is not None and кодировать(итог['барьер']) == кодировать(барьер)
            return итог

    def доставить(сам, наблюдать):
        with сам._доступ() as (каталог, журнал, состояние):
            сам._обновить(каталог, журнал, состояние, наблюдать)
            требовать(состояние is not None, 'повреждённая очередь')
            номер = состояние['подтверждено'] + 1
            if номер > len(состояние['сообщения']): return None
            запись = состояние['сообщения'][номер - 1]
            if состояние['доставлено'] < номер: сам._дописать(каталог, журнал, состояние, 'доставка', запись['ссылка'])
            return copy.deepcopy(запись)

    def подтвердить(сам, ссылка, наблюдать):
        with сам._доступ() as (каталог, журнал, состояние):
            сам._обновить(каталог, журнал, состояние, наблюдать)
            требовать(состояние is not None, 'повреждённая очередь')
            if _найти(состояние, ссылка)['ссылка']['номер'] <= состояние['подтверждено']: return сам._итог(состояние)
            _применить(copy.deepcopy(состояние), {'вид': 'подтверждение', 'данные': ссылка})
            сам._дописать(каталог, журнал, состояние, 'подтверждение', ссылка)
            return сам._итог(состояние)

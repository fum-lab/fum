def массив(значение, непустой=False):
    требовать(type(значение) is list and (not непустой or bool(значение)), 'ожидался массив')
    return значение


class РеестрВходов:
    """Локальная идентичность UUID. Проверка читает, регистрация отдельно пишет.

    Это не журнал допуска, не закрытие раунда и не очередь отмены. Полнота реестра
    является предусловием вызывающей стороны; другой пустой каталог её не доказывает.
    """
    def __init__(сам, каталог, репозиторий):
        сам.каталог = Path(каталог).absolute()
        корень = ОбъектыГит(репозиторий).корень
        сам.корень = корень
        требовать(сам.каталог == сам.каталог.resolve(), 'символическая ссылка в реестре')
        требовать(not сам.каталог.is_relative_to(корень), 'реестр входа должен находиться вне дерева')

    def проверить(сам, байты):
        требовать(сам.каталог == сам.каталог.resolve() and not сам.каталог.is_relative_to(сам.корень), 'подмена пути реестра')
        запись = прочитать(байты)
        поля(запись, ПОЛЯ)
        идентификатор(запись['идентификатор_задачи'])
        номер = идентификатор(запись['идентификатор_раунда'])
        файл = сам.каталог / (номер + '.json')
        требовать(not файл.is_symlink(), 'символическая ссылка вместо записи UUID')
        if файл.exists():
            требовать(файл.is_file() and файл.read_bytes() == байты, 'повтор UUID с другими байтами')
        return файл

    def зарегистрировать(сам, байты):
        файл = сам.проверить(байты)
        сам.каталог.mkdir(parents=True, exist_ok=True)
        сам.проверить(байты)
        дескриптор, имя = tempfile.mkstemp(prefix='.подготовка-', dir=сам.каталог)
        try:
            with os.fdopen(дескриптор, 'wb') as поток:
                поток.write(байты)
                поток.flush()
                os.fsync(поток.fileno())
            try:
                os.link(имя, файл)
            except FileExistsError:
                сам.проверить(байты)
            каталог = os.open(сам.каталог, os.O_RDONLY)
            try:
                os.fsync(каталог)
            finally:
                os.close(каталог)
        finally:
            os.unlink(имя)
        return файл


def _среда(значение):
    поля(значение, ('схема', 'компоненты', 'ограничения'))
    требовать(значение['схема'] == 'fum.среда-снимка.1', 'неизвестная схема среды')
    команды = set()
    for часть in массив(значение['компоненты'], True):
        поля(часть, ('имя', 'версия', 'команда'))
        for текст in часть.values():
            строка(текст)
            требовать(not any(ord(знак) < 32 for знак in текст), 'управляющий символ в среде')
        команда = часть['команда']
        требовать('/' not in команда and '\\' not in команда and команда not in команды, 'неоднозначная команда среды')
        команды.add(команда)
    for ограничение in массив(значение['ограничения'], True):
        строка(ограничение)
    return команды


def _план(значение, ссылки, листья, команды):
    поля(значение, ('схема', 'шаги', 'происхождение'))
    требовать(значение['схема'] == 'fum.план-снимка.1', 'неизвестная схема плана')
    фактические = []
    for узел in массив(значение['происхождение'], True):
        поля(узел, ('путь', 'вид', 'зависит_от'))
        фактические.append(путь(узел['путь']))
        for зависимость in массив(узел['зависит_от']):
            путь(зависимость)
        требовать(узел['вид'] == 'непрозрачные_байты' and узел['зависит_от'] == [], 'генераторы и заявленные производные не поддержаны')
    требовать(фактические == sorted(листья, key=lambda имя: имя.encode('utf-8')), 'происхождение не покрывает листья tree точно')
    for номер, шаг in enumerate(массив(значение['шаги'], True), 1):
        поля(шаг, ('номер', 'аргументы', 'класс', 'зависит_от', 'ожидаемый_исход', 'ссылки_на_инструменты', 'ссылки_на_правила'))
        требовать(число(шаг['номер']) == номер, 'неверный номер шага')
        требовать(шаг['класс'] in ('адресная', 'диагностическая', 'полная'), 'неизвестный класс шага')
        число(шаг['ожидаемый_исход'])
        требовать(шаг['ожидаемый_исход'] <= 255, 'неверный код исхода')
        предки = массив(шаг['зависит_от'])
        for предок in предки:
            требовать(0 < число(предок) < номер, 'будущий или неизвестный шаг')
        требовать(len(set(предки)) == len(предки), 'повтор зависимости шага')
        аргументы = массив(шаг['аргументы'], True)
        for аргумент in аргументы:
            строка(аргумент, пустая=True)
            требовать('\0' not in аргумент, 'NUL в аргументе')
        требовать(аргументы[0] in команды, 'команда отсутствует в профиле среды')
        for имя in ('ссылки_на_инструменты', 'ссылки_на_правила'):
            for ссылка in массив(шаг[имя], True):
                ссылки(ссылка)


def _зависимости(описания, объекты, дерево, листья, ссылки, локальные, профиль=None):
    покрытые = set()
    использованные = set()
    for описание in массив(описания):
        требовать(type(описание) is dict, 'неверная зависимость')
        вид = описание.get('вид')
        if вид == 'архив':
            поля(описание, ('вид', 'ссылка'))
            ссылки(описание['ссылка'])
            имя = описание['ссылка']['путь']
            требовать(имя not in покрытые, 'повтор зависимости')
            ссылки(описание['ссылка'])
            покрытые.add(имя)
        elif вид == 'gitlink':
            поля(описание, ('вид', 'путь', 'коммит', 'дерево', 'манифест'))
            имя = путь(описание['путь'])
            требовать(имя not in покрытые and имя in листья and листья[имя]['режим'] == '160000', 'неверный gitlink')
            требовать(описание['коммит'] == листья[имя]['объект'] and имя in локальные, 'gitlink недоступен')
            зависимость = ОбъектыГит(локальные[имя], профиль=профиль)
            требовать(зависимость.дерево_коммита(описание['коммит']) == описание['дерево'], 'дерево gitlink не совпадает')
            дочерние = зависимость.дерево(описание['дерево'])
            манифест = прочитать(ссылки(описание['манифест']))
            поля(манифест, ('схема', 'файлы'))
            требовать(манифест['схема'] == 'fum.файлы-зависимости.1', 'неизвестный манифест зависимости')
            имена = []
            for файл in массив(манифест['файлы']):
                поля(файл, ('ссылка', 'режим'))
                зависимость.проверить_ссылку(описание['дерево'], файл['ссылка'], дочерние)
                вложенный = файл['ссылка']['путь']
                имена.append(вложенный)
                зависимость.проверить_ссылку(описание['дерево'], файл['ссылка'], дочерние)
                требовать(файл['режим'] == дочерние[вложенный]['режим'], 'режим зависимости изменён')
            требовать(имена == sorted(дочерние, key=lambda имя: имя.encode()), 'неполные файлы зависимости')
            покрытые.add(имя)
            использованные.add(имя)
        else:
            raise ОшибкаВхода('неизвестный вид зависимости')
    требовать(использованные == set(локальные), 'лишняя локальная зависимость')
    требовать({имя for имя, лист in листья.items() if лист['режим'] == '160000'} <= покрытые, 'gitlink не охвачен манифестом')


def проверить_вход(корень, байты, оболочка, *, ожидаемый_коммит, ожидаемая_ветка, реестр, локальные_зависимости=None, профиль=None):
    """Только читает. Ожидаемые HEAD/ref сверяются как наблюдения, не атомарная гарантия."""
    профиль = профиль if профиль is not None else Профиль()
    with профиль.стадия('проверка_входа'):
        with профиль.стадия('каноническая_схема'):
            запись = проверить_конверт(байты, оболочка)
            поля(запись, ПОЛЯ)
            требовать(запись['версия'] == СХЕМА and запись['вид'] == 'вход', 'неизвестный вход')
            задача = идентификатор(запись['идентификатор_задачи'])
            идентификатор(запись['идентификатор_раунда'])
            требовать(запись['предыдущая_квитанция'] is None, 'поддержан только первый раунд без прежней квитанции')
            реестр.проверить(байты)
            объекты = ОбъектыГит(корень, профиль=профиль)
            требовать(реестр.корень == объекты.корень, 'реестр другого репозитория')
            требовать(запись['исходный_коммит'] == ожидаемый_коммит and запись['исходная_ветка'] == ожидаемая_ветка, 'неожиданное происхождение')
            объекты.наблюдать(ожидаемый_коммит, ожидаемая_ветка)
        with профиль.стадия('инвентарь_дерева'):
            дерево = запись['дерево_входа']
            листья = объекты.дерево(дерево)
            требовать(запись['запрос'] != запись['отчёт'], 'запрос и отчёт совпадают')
            for имя in ('запрос', 'отчёт'):
                объекты.ссылка(дерево, запись[имя], листья)

        def ссылки(ссылка):
            return объекты.проверить_ссылку(дерево, ссылка, листья)

        with профиль.стадия('граница_команд'):
            сообщения = проверить_экспорт(прочитать(ссылки(запись['граница_команд'])), задача)
            for основание in массив(запись['основание_полномочий'], True):
                поля(основание, ('номер_сообщения', 'действия'))
                номер = число(основание['номер_сообщения'])
                требовать(1 <= номер <= len(сообщения) and сообщения[номер - 1]['роль'] == 'user', 'полномочие не ссылается на user')
                действия = массив(основание['действия'], True)
                требовать(all(действие in ('проверка_байтов', 'подготовка_дерева') for действие in действия), 'действие не поддержано первым сегментом')
        with профиль.стадия('манифесты_и_план'):
            команды = _среда(прочитать(ссылки(запись['профиль_среды'])))
            политика = прочитать(ссылки(запись['политика_выхода']))
            поля(политика, ('схема', 'результаты'))
            требовать(политика['схема'] == 'fum.выход-снимка.1' and политика['результаты'] == [], 'выходное дерево не реализовано')
            _план(прочитать(ссылки(запись['план_проверок'])), ссылки, листья, команды)
        with профиль.стадия('зависимости'):
            _зависимости(запись['зависимости'], объекты, дерево, листья, ссылки, локальные_зависимости or {}, профиль)
        with профиль.стадия('все_сырые_байты'):
            запреты = (байты, оболочка, хэш(байты).encode())
            for лист in листья.values():
                if лист['режим'] != '160000':
                    содержимое = объекты.прочитать(лист['объект'], 'blob')
                    требовать(not any(запрет in содержимое for запрет in запреты), 'обратная байтовая ссылка на вход или конверт')
        объекты.наблюдать(ожидаемый_коммит, ожидаемая_ветка)
        реестр.проверить(байты)
        return {'схема': 'fum.проверка-входа.1', 'статус': 'сырые_байты_проверены', 'хэш_входа': хэш(байты),
                'дерево_входа': дерево, 'исполнение_разрешено': False, 'коммит_разрешён': False,
                'очередь_доставки': 'не_реализована', 'происхождение': 'структура_и_байты_без_доказательства_семантики'}



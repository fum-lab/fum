#!/usr/bin/env python3
"""Проверка связи уже проверенных v3-свидетельств с коммитом, только чтение."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

from отчёты_о_запусках_проверок import (
    ОшибкаОтчёта,
    добавить_часть_отпечатка,
    проверить_аналитический_ключ,
)


ФЛАГИ_РАЗНИЦЫ = ("--binary", "--no-ext-diff", "--no-textconv", "--ignore-submodules=none")


def выполнить_чтение_репозитория(корень: Path, *аргументы: str) -> bytes:
    # Убираем также модификаторы pathspec и переменные трассировки/переадресации.
    границы_настроек = {"GIT_CONFIG_SYSTEM", "GIT_CONFIG_GLOBAL", "GIT_CONFIG_NOSYSTEM"}
    окружение = {имя: значение for имя, значение in os.environ.items() if not имя.startswith("GIT_") or имя in границы_настроек}
    окружение.update({"GIT_OPTIONAL_LOCKS": "0", "GIT_NO_REPLACE_OBJECTS": "1", "GIT_NO_LAZY_FETCH": "1", "LC_ALL": "C"})
    итог = subprocess.run(
        ["git", "-C", str(корень), "-c", "core.fsmonitor=false", *аргументы],
        capture_output=True, env=окружение, check=False,
    )
    if итог.returncode:
        raise ОшибкаОтчёта("чтение локальных объектов Git не выполнено: " + итог.stderr.decode("utf-8", errors="replace").strip())
    return итог.stdout


def пути_границы(сессия: str) -> list[str]:
    проверить_аналитический_ключ(сессия, "сессия")
    if (
        not сессия.startswith("Журнал/")
        or len(Path(сессия).parts) != 2
        or any(знак in сессия for знак in "*?[]")
    ):
        raise ОшибкаОтчёта("сессия должна обозначать точную папку Журнала")
    # Буквальный контракт v3: не добавлять флаги или префиксы к старым байтам diff.
    запуски = f"{сессия}/материалы/запуски-проверок"
    return [
        ".", f":(exclude){сессия}/отчёт.md", f":(exclude){запуски}",
        f":(exclude){запуски}/**", ":(top,exclude,literal)Proyekcii",
        ":(top,exclude,glob)Proyekcii/**",
    ]


def проверить_непосредственную_границу(
    корень: Path, коммит: str, пути: list[str], дерево: bytes,
) -> bytes:
    читать = lambda *аргументы: выполнить_чтение_репозитория(корень, *аргументы)
    if читать("rev-parse", "--verify", "HEAD").strip() != коммит.encode("ascii"):
        raise ОшибкаОтчёта("непосредственная граница требует HEAD выбранного коммита")
    индекс = читать("ls-files", "--stage", "-v", "--full-name", "-z")
    записи = []
    for строка in индекс.split(b"\0"):
        if not строка:
            continue
        if not строка.startswith(b"H "):
            raise ОшибкаОтчёта("флаги индекса могут скрывать рабочие изменения")
        метаданные, имя = строка[2:].split(b"\t", 1)
        права, объект, стадия = метаданные.split(b" ")
        if стадия != b"0":
            raise ОшибкаОтчёта("индекс содержит неразрешённые стадии")
        записи.append((права, объект, имя))
    ожидаемые = []
    for строка in дерево.split(b"\0"):
        if строка:
            метаданные, имя = строка.split(b"\t", 1)
            права, _, объект = метаданные.split(b" ")
            ожидаемые.append((права, объект, имя))
    if записи != ожидаемые:
        raise ОшибкаОтчёта("индекс не совпадает с деревом выбранного коммита")
    состояние = читать("status", "--porcelain=v2", "-z", "--untracked-files=all", "--ignore-submodules=none", "--", *пути)
    for строка in состояние.split(b"\0"):
        if строка.startswith((b"1 ", b"2 ", b"u ")):
            части = строка.split(b" ", 8)
            if len(части) > 2 and части[2].startswith(b"S") and части[2][2:] != b"..":
                raise ОшибкаОтчёта("рабочее дерево содержит изменённый подмодуль")
    if читать("diff", *ФЛАГИ_РАЗНИЦЫ, "--", *пути):
        raise ОшибкаОтчёта("обнаружены неиндексированные канонические изменения")
    if читать("ls-files", "--others", "--exclude-standard", "-z", "--", *пути):
        raise ОшибкаОтчёта("обнаружен неотслеживаемый канонический вход")
    return индекс


def связать_отпечаток_с_коммитом(
    корень_репозитория: str | Path,
    сессия: str,
    коммит: str,
    отпечаток_закрытия: str,
    отпечаток_запуска: str,
    режим: str = "исторический",
) -> dict[str, str]:
    """Равенство SHA не заменяет проверку отчёта, полномочий и результата."""
    корень = Path(корень_репозитория).resolve()
    пути = пути_границы(сессия)
    if режим not in {"исторический", "после-коммита"}:
        raise ОшибкаОтчёта("неизвестный режим связи отпечатка")
    if not re.fullmatch(r"(?:[0-9a-f]{40}|[0-9a-f]{64})", коммит):
        raise ОшибкаОтчёта("коммит должен быть полным OID")
    for значение in (отпечаток_закрытия, отпечаток_запуска):
        if not re.fullmatch(r"sha256:[0-9a-f]{64}", значение):
            raise ОшибкаОтчёта("неверный формат отпечатка v3")
    читать = lambda *аргументы: выполнить_чтение_репозитория(корень, *аргументы)
    # Читаем сам объект: shallow-граница и grafts не должны скрыть родителей.
    if Path(os.fsdecode(читать("rev-parse", "--show-toplevel").rstrip(b"\n"))).resolve() != корень:
        raise ОшибкаОтчёта("переданный корень не совпадает с корнем checkout")
    if читать("rev-parse", "--verify", коммит).strip() != коммит.encode("ascii"):
        raise ОшибкаОтчёта("OID выбранного объекта не является полным")
    if читать("cat-file", "-t", коммит).strip() != b"commit":
        raise ОшибкаОтчёта("выбранный OID не является объектом коммита")
    объект = читать("cat-file", "commit", коммит)
    заголовки = объект.split(b"\n\n", 1)[0].split(b"\n")
    родители = [строка[7:] for строка in заголовки if строка.startswith(b"parent ")]
    if len(родители) != 1:
        raise ОшибкаОтчёта("требуется коммит с ровно одним родителем")
    родитель = родители[0].decode("ascii")
    if читать("cat-file", "-t", родитель).strip() != b"commit":
        raise ОшибкаОтчёта("родитель не является доступным коммитом")
    непосредственно = режим == "после-коммита"
    if непосредственно:
        настройки = читать("config", "--null", "--list")
        if any(re.match(rb"filter\..*\.(clean|process)\n[^\0]+", строка) for строка in настройки.split(b"\0")):
            raise ОшибкаОтчёта("исполняемые фильтры не позволяют доказать чистоту одним чтением")
        дерево = читать("ls-tree", "-r", "-z", коммит)
        if any(строка.startswith(b"160000 ") for строка in дерево.split(b"\0")):
            raise ОшибкаОтчёта("непосредственный режим пока не поддерживает gitlink")
        граница = проверить_непосредственную_границу(корень, коммит, пути, дерево)
        сравнение = ("--cached", родитель)
    else:
        сравнение = (родитель, коммит)
    разница = читать("diff", *ФЛАГИ_РАЗНИЦЫ, *сравнение, "--", *пути)
    хэш = hashlib.sha256()
    добавить_часть_отпечатка(хэш, "вершина", родители[0])
    добавить_часть_отпечатка(хэш, "индекс", разница)
    добавить_часть_отпечатка(хэш, "рабочее_дерево", b"")
    кандидат = "sha256:" + хэш.hexdigest()
    if непосредственно:
        после = проверить_непосредственную_границу(корень, коммит, пути, дерево)
        if после != граница or читать("diff", *ФЛАГИ_РАЗНИЦЫ, *сравнение, "--", *пути) != разница:
            raise ОшибкаОтчёта("граница изменилась во время чтения")
    return {
        "схема": "fum.связь-отпечатка-с-коммитом.1", "коммит": коммит,
        "родитель": родитель, "сессия": сессия, "режим": режим,
        "состояние": "подтверждён" if кандидат == отпечаток_закрытия == отпечаток_запуска else "не восстановлен",
        "кандидат": кандидат,
    }


def главная() -> int:
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument("--корень-репозитория", default=".")
    разбор.add_argument("--сессия", required=True)
    разбор.add_argument("--коммит", required=True)
    разбор.add_argument("--отпечаток-закрытия", required=True)
    разбор.add_argument("--отпечаток-запуска", required=True)
    разбор.add_argument("--режим", choices=("исторический", "после-коммита"), default="исторический")
    параметры = разбор.parse_args()
    try:
        итог = связать_отпечаток_с_коммитом(**vars(параметры))
    except (ОшибкаОтчёта, OSError, ValueError) as ошибка:
        print(f"Ошибка: {ошибка}", file=sys.stderr)
        return 1
    print(json.dumps(итог, ensure_ascii=False, sort_keys=True))
    return 0 if итог["состояние"] == "подтверждён" else 2


if __name__ == "__main__":
    raise SystemExit(главная())

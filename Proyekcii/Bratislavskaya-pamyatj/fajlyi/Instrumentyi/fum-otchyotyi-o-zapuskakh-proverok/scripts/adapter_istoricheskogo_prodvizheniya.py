"""Согласовать точный before с базовой фикстурой профиля продвижения.

Это прямые ссылки для позиционных вызовов профиля. Переименованные keyword
не поддержаны; monkeypatch экспортов адаптера не меняет globals истории.
Подготовка выполняется до измеряемого этапа и не оборачивает вызовы.
"""
import hashlib
from pathlib import Path
from types import SimpleNamespace


def создать_адаптер_истории(исторический_модуль):
    ожидаемый = 'c8695da01383f3c131d8eb82dc9df90d43adbe7ebcbf54661349ec6199002fce'
    if hashlib.sha256(Path(исторический_модуль.__file__).read_bytes()).hexdigest() != ожидаемый:
        raise ValueError('Адаптер требует точные байты исторического before')
    return SimpleNamespace(
        выполнить_гит=исторический_модуль.git,
        идентификатор_объекта=исторический_модуль.oid,
        команда_гита=исторический_модуль.команда_git,
        среда=исторический_модуль.среда,
        перейти=исторический_модуль.перейти,
        Отказ=исторический_модуль.Отказ,
        subprocess=исторический_модуль.subprocess,
    )

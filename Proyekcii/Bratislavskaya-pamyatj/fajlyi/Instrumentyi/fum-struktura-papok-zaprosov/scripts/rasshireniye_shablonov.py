class ОшибкаРасширения(RuntimeError):
    """Вход не допускает запись."""


class Наблюдение:
    """Вложенные интервалы; диагностические данные не входят в план."""

    def __init__(сам):
        сам.записи = []
        сам.стек = []

    @contextmanager
    def этап(сам, имя):
        запись = {'номер': len(сам.записи) + 1, 'этап': имя,
                  'родитель': сам.стек[-1] if сам.стек else None,
                  'начало_UTC': datetime.now(timezone.utc).isoformat(), 'исход': 'отказ'}
        сам.записи.append(запись)
        сам.стек.append(запись['номер'])
        начало = time.perf_counter_ns()
        процесс = time.process_time_ns()
        try:
            yield запись
            запись['исход'] = 'успех'
        finally:
            запись['длительность_нс'] = time.perf_counter_ns() - начало
            запись['CPU_процесса_нс'] = time.process_time_ns() - процесс
            запись['конец_UTC'] = datetime.now(timezone.utc).isoformat()
            сам.стек.pop()


def сериализовать(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + '\n'


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def _поля(значение, ожидаемые, имя):
    if not isinstance(значение, dict) or set(значение) != set(ожидаемые):
        raise ОшибкаРасширения(f'неверные поля: {имя}')


def _текст(значение, имя):
    if (not isinstance(значение, str) or not значение.strip()
            or any(unicodedata.category(знак) in {'Cc', 'Cs'} and знак not in '\n\t'
                   for знак in значение)):
        raise ОшибкаРасширения(f'не заполнено или повреждено поле: {имя}')


def _путь(корень, относительный):
    if (not isinstance(относительный, str) or not относительный
            or '\\' in относительный or '\x00' in относительный):
        raise ОшибкаРасширения('неканонический путь')
    путь = PurePosixPath(относительный)
    if путь.is_absolute() or '..' in путь.parts or путь.as_posix() != относительный:
        raise ОшибкаРасширения('путь выходит из разрешённой области')
    текущий = корень
    for часть in путь.parts:
        if текущий.exists():
            if not текущий.is_dir():
                raise ОшибкаРасширения('предок пути не является каталогом')
            имена = [п.name for п in текущий.iterdir()]
            ключ = unicodedata.normalize('NFC', часть).casefold()
            совпадения = [имя for имя in имена if unicodedata.normalize('NFC', имя).casefold() == ключ]
            if совпадения and совпадения != [часть]:
                raise ОшибкаРасширения('коллизия или неверный регистр пути')
        текущий /= часть
        if текущий.is_symlink():
            raise ОшибкаРасширения('символическая ссылка в пути')
    if текущий.exists() and not текущий.is_file():
        raise ОшибкаРасширения('цель не является обычным файлом')
    return текущий


def _снимок(путь):
    if not путь.exists():
        return None
    return {'sha256': хэш(путь.read_bytes()), 'режим': stat.S_IMODE(путь.stat().st_mode)}


def _зависимости(корень, дополнительные=()):
    результат = {}
    for имя in sorted(set(ЗАВИСИМОСТИ) | set(дополнительные)):
        снимок = _снимок(_путь(корень, имя))
        if снимок is None:
            raise ОшибкаРасширения(f'отсутствует зависимость: {имя}')
        if имя in ИСПОЛНЯЕМЫЕ_БАЙТЫ and снимок['sha256'] != хэш(ИСПОЛНЯЕМЫЕ_БАЙТЫ[имя]):
            raise ОшибкаРасширения('исполняемый контур не совпадает с целевым checkout')
        результат[имя] = снимок
    return результат


def _описание(вход):
    _поля(вход, ('схема', 'тип', 'основание', 'версия', 'разделы', 'шаблон'), 'описание')
    if вход['схема'] != 'fum.расширение-шаблона.1' or вход['основание'] != 'вопрос':
        raise ОшибкаРасширения('поддерживается только совместимое семейство вопросов')
    if not isinstance(вход['тип'], str) or not re.fullmatch('[а-яё]+(?:-[а-яё]+)*', вход['тип']):
        raise ОшибкаРасширения('тип должен иметь русское имя')
    if type(вход['версия']) is not int or вход['версия'] < 1:
        raise ОшибкаРасширения('неверная версия типа')
    if not isinstance(вход['разделы'], list):
        raise ОшибкаРасширения('разделы должны быть массивом')
    пары = []
    for раздел in вход['разделы']:
        _поля(раздел, ('заголовок', 'поле'), 'раздел')
        _текст(раздел['заголовок'], 'заголовок раздела')
        if not re.fullmatch('[А-ЯЁа-яё][А-ЯЁа-яё -]*', раздел['заголовок']):
            raise ОшибкаРасширения('неверный заголовок раздела')
        if not isinstance(раздел['поле'], str) or not re.fullmatch('[а-яё]+(?:_[а-яё]+)*', раздел['поле']):
            raise ОшибкаРасширения('неверное поле раздела')
        пары.append((раздел['заголовок'], раздел['поле']))
    if (пары[:2] != list(ОБЯЗАТЕЛЬНЫЕ[:2]) or пары[-2:] != list(ОБЯЗАТЕЛЬНЫЕ[-2:])
            or len({п[0] for п in пары}) != len(пары)
            or len({п[1] for п in пары} | {'заголовок', 'кратко'}) != len(пары) + 2):
        raise ОшибкаРасширения('несовместимые разделы и поля вопроса')
    _текст(вход['шаблон'], 'шаблон')
    # Ограниченная грамматика сохраняет активный каркас и положение каждого поля.
    ожидаемый = '# {{заголовок}}\n\n{{кратко}}\n\n' + '\n\n'.join(
        '## ' + заголовок + '\n\n{{' + поле + '}}' for заголовок, поле in пары) + '\n'
    if вход['шаблон'] != ожидаемый:
        raise ОшибкаРасширения('несовместимый шаблон: поля, порядок или оформление')
    return {ключ: значение for ключ, значение in вход.items() if ключ != 'шаблон'}


def _имена_типа(тип):
    return f'{ОБЛАСТЬ}/типы/{тип}.json', f'{ОБЛАСТЬ}/шаблоны/{тип}.md.шаблон'


def _читать_тип(корень, тип):
    if not isinstance(тип, str) or not re.fullmatch('[а-яё]+(?:-[а-яё]+)*', тип):
        raise ОшибкаРасширения('неверный тип')
    имя, шаблон = _имена_типа(тип)
    try:
        описание = json.loads(_путь(корень, имя).read_bytes())
        описание['шаблон'] = _путь(корень, шаблон).read_bytes().decode('utf-8')
    except (OSError, ValueError, TypeError) as ошибка:
        raise ОшибкаРасширения('тип не установлен или повреждён') from ошибка
    _описание(описание)
    if описание['тип'] != тип:
        raise ОшибкаРасширения('имя установленного типа не совпадает')
    return описание


def проверить_установленные_типы(корень):
    """Ранняя проверка расширений; историческое отсутствие каталога допустимо."""
    каталог = корень / ОБЛАСТЬ / 'типы'
    if каталог.is_symlink():
        raise ОшибкаРасширения('символическая ссылка вместо каталога типов')
    if not каталог.exists():
        return
    if not каталог.is_dir():
        raise ОшибкаРасширения('каталог типов не является каталогом')
    for путь in sorted(каталог.iterdir()):
        if путь.suffix != '.json':
            raise ОшибкаРасширения('неизвестный файл каталога типов')
        _читать_тип(корень, путь.stem)


def _результат_расширения(корень, вход):
    описание = _описание(вход)
    имя, шаблон = _имена_типа(вход['тип'])
    цели = {имя: сериализовать(описание), шаблон: вход['шаблон']}
    существует = [_путь(корень, путь).exists() for путь in цели]
    if any(существует):
        if not all(существует):
            raise ОшибкаРасширения('неполный установленный тип')
        прежнее = _читать_тип(корень, вход['тип'])
        if прежнее != вход:
            if вход['версия'] != прежнее['версия'] + 1:
                raise ОшибкаРасширения('изменение требует следующей версии типа')
            прежние = [(р['заголовок'], р['поле']) for р in прежнее['разделы']]
            новые = [(р['заголовок'], р['поле']) for р in вход['разделы']]
            if [пара for пара in новые if пара in прежние] != прежние:
                raise ОшибкаРасширения('несовместимое удаление или перестановка прежних полей')
    elif вход['версия'] != 1:
        raise ОшибкаРасширения('новый тип начинается с версии 1')
    return цели, ()


def _проверка_вопросов():
    имя = 'проверка_вопросов_шаблона'
    if имя not in sys.modules:
        путь = Path(__file__).resolve().parents[3] / ПРОВЕРКА_ВОПРОСОВ
        if путь.read_bytes() != ИСПОЛНЯЕМЫЕ_БАЙТЫ[ПРОВЕРКА_ВОПРОСОВ]:
            raise ОшибкаРасширения('исполняемый валидатор изменился после загрузки')
        спецификация = importlib.util.spec_from_file_location(имя, путь)
        модуль = importlib.util.module_from_spec(спецификация)
        sys.modules[имя] = модуль
        спецификация.loader.exec_module(модуль)
    return sys.modules[имя]


def _результат_документа(корень, вход):
    _поля(вход, ('схема', 'тип', 'путь', 'поля'), 'документ')
    if вход['схема'] != 'fum.документ-шаблона.1':
        raise ОшибкаРасширения('неверная схема документа')
    путь = _путь(корень, вход['путь'])
    относительный = PurePosixPath(вход['путь'])
    if (len(относительный.parts) != 2 or относительный.parts[0] != 'Вопросы'
            or относительный.name == 'README.md' or относительный.suffix != '.md'):
        raise ОшибкаРасширения('разрешены только отдельные документы Вопросы/*.md')
    описание = _читать_тип(корень, вход['тип'])
    имена = {'заголовок', 'кратко'} | {р['поле'] for р in описание['разделы']}
    _поля(вход['поля'], имена, 'смысловые поля')
    проверка = _проверка_вопросов()
    for имя, значение in вход['поля'].items():
        _текст(значение, имя)
        видимый = ''.join(проверка.visible_markdown_lines(значение)).strip()
        if not видимый or каркас.МАРКЕР_НЕЗАПОЛНЕННОГО_ШАБЛОНА in значение:
            raise ОшибкаРасширения(f'незаполненное поле: {имя}')
        if проверка.markdown_sections(значение) or re.search(r'^ {0,3}# ', видимый, re.M):
            raise ОшибкаРасширения(f'поле меняет структуру документа: {имя}')
    if '\n' in вход['поля']['заголовок']:
        raise ОшибкаРасширения('заголовок должен быть однострочным')
    дополнительные = set(_имена_типа(вход['тип']))
    for имя in ('источники', 'документация'):
        ссылки = проверка.iter_links_in_text(вход['поля'][имя], путь)
        if not ссылки:
            raise ОшибкаРасширения(f'поле {имя} требует действующей ссылки')
        локальные = set()
        for ссылка in ссылки:
            цель = проверка.resolve_local_target(ссылка, корень)
            if цель is None:
                if not проверка.is_external_link(ссылка.target):
                    raise ОшибкаРасширения('локальная ссылка должна содержать путь файла')
                continue
            if (цель.actual is None or цель.case_mismatch or not цель.actual.is_file()
                    or цель.actual.suffix != '.md' or проверка.path_uses_symlink(цель.actual, корень)):
                raise ОшибкаРасширения('неверная локальная ссылка')
            if цель.actual in локальные:
                raise ОшибкаРасширения('повтор локальной ссылки')
            локальные.add(цель.actual)
            дополнительные.add(цель.actual.relative_to(корень).as_posix())
            if имя == 'документация':
                # Независимый валидатор разрешает только существующие цели.
                # Здесь вопрос ещё не записан: сравниваем точный будущий путь.
                есть = False
                for обратная in проверка.iter_markdown_links(цель.actual):
                    адрес = unquote(обратная.target).split('#', 1)[0].split('?', 1)[0]
                    if адрес and not проверка.is_external_link(адрес):
                        ожидаемый = проверка.lexical_absolute(цель.actual.parent / адрес)
                        if ожидаемый == путь:
                            есть = True
                if not есть:
                    raise ОшибкаРасширения('отсутствует или неверна обратная ссылка на вопрос')
        if имя == 'документация' and not локальные:
            raise ОшибкаРасширения('документация требует локальную Markdown-ссылку')
    текст = каркас._заполнить_шаблон(описание['шаблон'], вход['поля'])
    разделы = проверка.markdown_sections(текст)
    if [р.title for р in разделы] != [р['заголовок'] for р in описание['разделы']]:
        raise ОшибкаРасширения('значения скрывают или изменяют обязательные разделы')
    if путь.exists() and путь.read_bytes() != текст.encode('utf-8'):
        raise ОшибкаРасширения('существующий документ отличается; миграция не поддерживается')
    return {вход['путь']: текст}, дополнительные


def _построить(корень, режим, вход, наблюдение):
    корень = Path(корень).resolve(strict=True)
    with наблюдение.этап('проверка входа'):
        цели, дополнительные = (_результат_расширения if режим == 'расширение' else _результат_документа)(корень, вход)
    with наблюдение.этап('снимок зависимостей'):
        зависимости = _зависимости(корень, дополнительные)
    with наблюдение.этап('точный план и diff'):
        операции = []
        результаты = {}
        for имя, текст in sorted(цели.items()):
            путь = _путь(корень, имя)
            до = путь.read_bytes() if путь.exists() else b''
            результаты[имя] = {'sha256': хэш(текст.encode('utf-8')),
                'режим': stat.S_IMODE(путь.stat().st_mode) if путь.exists() else 0o644}
            if путь.exists() and до == текст.encode('utf-8'):
                continue
            операции.append({'путь': имя, 'до': _снимок(путь), 'прежний_текст': до.decode('utf-8'), 'текст': текст,
                'после': результаты[имя],
                'diff': ''.join(difflib.unified_diff(до.decode('utf-8').splitlines(True),
                    текст.splitlines(True), fromfile=имя, tofile=имя))})
        план = {'схема': 'fum.план-шаблона.1', 'режим': режим, 'вход': вход,
                'зависимости': зависимости, 'операции': операции, 'результаты': результаты}
        план['sha256'] = хэш(сериализовать(план).encode('utf-8'))
        return план


def план_расширения(корень, вход, наблюдение=None):
    наблюдение = наблюдение or Наблюдение()
    with наблюдение.этап('план расширения'):
        return _построить(корень, 'расширение', вход, наблюдение)


def план_документа(корень, вход, наблюдение=None):
    наблюдение = наблюдение or Наблюдение()
    with наблюдение.этап('план документа'):
        return _построить(корень, 'документ', вход, наблюдение)


def применить_план(корень, план, наблюдение=None):
    наблюдение = наблюдение or Наблюдение()
    корень = Path(корень).resolve(strict=True)
    with наблюдение.этап('применение'):
        with наблюдение.этап('проверка сохранённого плана'):
            _поля(план, ('схема', 'режим', 'вход', 'зависимости', 'операции', 'результаты', 'sha256'), 'план')
            без_хэша = {к: з for к, з in план.items() if к != 'sha256'}
            if (план['схема'] != 'fum.план-шаблона.1' or план['режим'] not in ('расширение', 'документ')
                    or план['sha256'] != хэш(сериализовать(без_хэша).encode('utf-8'))):
                raise ОшибкаРасширения('повреждённый план')
            for имя, снимок in план['зависимости'].items():
                if _снимок(_путь(корень, имя)) != снимок:
                    raise ОшибкаРасширения(f'план устарел: зависимость {имя}')
            новый = _построить(корень, план['режим'], план['вход'], наблюдение)
            if новый['зависимости'] != план['зависимости']:
                raise ОшибкаРасширения('план устарел: состав зависимостей')
            if новый['результаты'] != план['результаты']:
                raise ОшибкаРасширения('план устарел: полный снимок результатов')
            цели, _ = (_результат_расширения if план['режим'] == 'расширение' else _результат_документа)(корень, план['вход'])
            if not isinstance(план['операции'], list):
                raise ОшибкаРасширения('неверный список операций')
            посещённые = set()
            for операция in план['операции']:
                _поля(операция, ('путь', 'до', 'прежний_текст', 'текст', 'после', 'diff'), 'операция')
                имя = операция['путь']
                if имя not in цели or имя in посещённые or операция['текст'] != цели[имя]:
                    raise ОшибкаРасширения('подменённый результат плана')
                посещённые.add(имя)
                прежний = операция['прежний_текст']
                if not isinstance(прежний, str):
                    raise ОшибкаРасширения('неверный прежний текст')
                if операция['до'] is None:
                    if прежний != '':
                        raise ОшибкаРасширения('неверный отсутствующий вход')
                else:
                    _поля(операция['до'], ('sha256', 'режим'), 'снимок входа')
                    if операция['до']['sha256'] != хэш(прежний.encode('utf-8')):
                        raise ОшибкаРасширения('подменённый прежний текст')
                ожидаемый = ''.join(difflib.unified_diff(прежний.splitlines(True), цели[имя].splitlines(True), fromfile=имя, tofile=имя))
                if операция['diff'] != ожидаемый or операция['после'] != новый['результаты'][имя]:
                    raise ОшибкаРасширения('подменённый предпросмотр или снимок результата')
            if not новый['операции']:
                # Повтор разрешён только для точного результата всего сохранённого плана.
                for операция in план['операции']:
                    if _снимок(_путь(корень, операция['путь'])) != операция['после']:
                        raise ОшибкаРасширения('план устарел: результат или режим файла')
                return {'схема': 'fum.применение-шаблона.1', 'план': план['sha256'], 'повтор': True, 'файлов': 0}
            if новый != план:
                raise ОшибкаРасширения('план устарел или изменён; получите новый предпросмотр')
        with наблюдение.этап('установка файлов'):
            подготовленные = [каркас.PreparedFile(PurePosixPath(о['путь']), о['текст'].encode('utf-8'), о['после']['режим'])
                              for о in план['операции']]
            try:
                каркас._apply_prepared_transaction(корень, подготовленные)
            except каркас.LayoutError as ошибка:
                raise ОшибкаРасширения('запись отклонена; выполнен откат файловой транзакции') from ошибка
        return {'схема': 'fum.применение-шаблона.1', 'план': план['sha256'], 'повтор': False, 'файлов': len(подготовленные)}


def _без_повторов(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ОшибкаРасширения('повторный ключ JSON')
        результат[ключ] = значение
    return результат



def записать_состояние_установки(
    служебный: Path,
    состояние: Mapping[str, Any],
    ожидаемое_предыдущее: Mapping[str, Any] | None,
) -> None:
    путь = служебный / "состояние.json"
    временный = служебный / имя_временного_состояния(
        str(состояние["транзакция"])
    )

    if ожидаемое_предыдущее is None:
        if состояние.get("фаза") != "строится":
            raise ОшибкаКонтракта(
                "Первый журнал установки обязан начинаться с фазы строится"
            )
    else:
        предыдущее = dict(ожидаемое_предыдущее)
        новое = dict(состояние)
        предыдущая_фаза = предыдущее.get("фаза")
        новая_фаза = новое.get("фаза")
        допустимые_переходы = {
            ("строится", "подготовлено"),
            ("подготовлено", "прежнее_зарезервировано"),
            ("подготовлено", "новое_установлено"),
            ("прежнее_зарезервировано", "новое_установлено"),
            ("новое_установлено", "принято"),
            ("строится", "откачено"),
            ("подготовлено", "откачено"),
            ("прежнее_зарезервировано", "откачено"),
            ("новое_установлено", "откачено"),
        }
        предыдущее_без_фазы = dict(предыдущее)
        новое_без_фазы = dict(новое)
        предыдущее_без_фазы.pop("фаза", None)
        новое_без_фазы.pop("фаза", None)
        if (
            (предыдущая_фаза, новая_фаза) not in допустимые_переходы
            or канонические_байты(предыдущее_без_фазы)
            != канонические_байты(новое_без_фазы)
        ):
            raise ОшибкаКонтракта("Недопустимый переход фазового журнала")

    def проверить_предыдущее_состояние() -> (
        tuple[int, int, int, int, int] | None
    ):
        try:
            сведения_до = путь.lstat()
        except FileNotFoundError:
            if ожидаемое_предыдущее is not None:
                raise ОшибкаКонтракта(
                    "Предыдущее состояние установки исчезло"
                )
            return None
        проверить_точное_имя_дочернего_пути(
            служебный,
            путь.name,
            "фазового журнала установки",
        )
        if ожидаемое_предыдущее is None:
            raise ОшибкаКонтракта(
                "Первый журнал установки не может заменять существующий файл"
            )
        байты = прочитать_точный_обычный_файл(
            путь,
            "предыдущее состояние установки",
        )
        сведения_после = путь.lstat()
        свидетельство_до = (
            сведения_до.st_dev,
            сведения_до.st_ino,
            сведения_до.st_mode,
            сведения_до.st_size,
            сведения_до.st_mtime_ns,
        )
        свидетельство_после = (
            сведения_после.st_dev,
            сведения_после.st_ino,
            сведения_после.st_mode,
            сведения_после.st_size,
            сведения_после.st_mtime_ns,
        )
        if (
            свидетельство_до != свидетельство_после
            or байты != канонические_байты(ожидаемое_предыдущее)
        ):
            raise ОшибкаКонтракта(
                "Предыдущее состояние установки было подменено"
            )
        return свидетельство_после

    исходное_свидетельство = проверить_предыдущее_состояние()
    try:
        временный.lstat()
    except FileNotFoundError:
        pass
    else:
        проверить_точное_имя_дочернего_пути(
            служебный,
            временный.name,
            "временного фазового журнала",
        )
        raise ОшибкаКонтракта(
            "Временный журнал установки уже существует и не может быть перезаписан"
        )
    записать_обычный_файл(временный, канонические_байты(состояние), "100644")
    проверить_точное_имя_дочернего_пути(
        служебный,
        временный.name,
        "записанного временного фазового журнала",
    )
    сведения_временного = временный.lstat()
    свидетельство_временного = (
        сведения_временного.st_dev,
        сведения_временного.st_ino,
        сведения_временного.st_mode,
        сведения_временного.st_size,
        сведения_временного.st_mtime_ns,
    )
    if проверить_предыдущее_состояние() != исходное_свидетельство:
        raise ОшибкаКонтракта(
            "Предыдущее состояние установки изменилось перед заменой"
        )
    текущий_временный = временный.lstat()
    if свидетельство_временного != (
        текущий_временный.st_dev,
        текущий_временный.st_ino,
        текущий_временный.st_mode,
        текущий_временный.st_size,
        текущий_временный.st_mtime_ns,
    ):
        raise ОшибкаКонтракта(
            "Временный журнал установки изменился перед заменой"
        )
    os.replace(временный, путь)
    синхронизировать_каталог(служебный)


def удалить_безопасное_дерево(
    путь: Path,
    ожидаемый_снимок: Mapping[str, Any] | None = None,
    назначение: str = "служебное дерево",
    *,
    допустимые_режимы_корня: frozenset[int] = frozenset({0o755}),
) -> None:
    свидетельства: dict[Path, tuple[int, int, int, int, int]] = {}
    фактические_каталоги: list[str] = []
    фактические_файлы: dict[str, dict[str, Any]] = {}

    def обследовать(текущий: Path, относительный: str = "") -> None:
        сведения = текущий.lstat()
        if stat.S_ISLNK(сведения.st_mode) or not stat.S_ISDIR(сведения.st_mode):
            raise ОшибкаКонтракта(f"Нельзя удалить небезопасное дерево: {текущий}")
        режим_каталога = stat.S_IMODE(сведения.st_mode)
        if (
            (относительный and режим_каталога != 0o755)
            or (
                not относительный
                and режим_каталога not in допустимые_режимы_корня
            )
        ):
            raise ОшибкаКонтракта(
                f"{назначение} содержит каталог неверного режима: "
                f"{относительный or '.'}"
            )
        if относительный:
            фактические_каталоги.append(относительный)
        свидетельства[текущий] = (
            сведения.st_dev,
            сведения.st_ino,
            сведения.st_mode,
            сведения.st_size,
            сведения.st_mtime_ns,
        )
        for элемент in sorted(
            os.scandir(текущий),
            key=lambda запись: запись.name.encode("utf-8"),
        ):
            дочерний = текущий / элемент.name
            дочерний_относительный = (
                f"{относительный}/{элемент.name}"
                if относительный
                else элемент.name
            )
            сведения_элемента = элемент.stat(follow_symlinks=False)
            if stat.S_ISDIR(сведения_элемента.st_mode):
                обследовать(дочерний, дочерний_относительный)
            elif stat.S_ISREG(сведения_элемента.st_mode):
                режим = stat.S_IMODE(сведения_элемента.st_mode)
                if режим not in {0o644, 0o755}:
                    raise ОшибкаКонтракта(
                        f"{назначение} содержит файл неверного режима: "
                        f"{дочерний_относительный}"
                    )
                данные = прочитать_точный_обычный_файл(
                    дочерний,
                    f"{назначение}: {дочерний_относительный}",
                    режим=режим,
                )
                фактические_файлы[дочерний_относительный] = {
                    "хэш": хэш_байтов(данные),
                    "режим": "100755" if режим == 0o755 else "100644",
                    "размер": len(данные),
                }
                свидетельства[дочерний] = (
                    сведения_элемента.st_dev,
                    сведения_элемента.st_ino,
                    сведения_элемента.st_mode,
                    сведения_элемента.st_size,
                    сведения_элемента.st_mtime_ns,
                )
            else:
                raise ОшибкаКонтракта(
                    f"Служебное дерево содержит небезопасный объект: {дочерний}"
                )

    def удалить(текущий: Path) -> None:
        for элемент in sorted(
            os.scandir(текущий),
            key=lambda запись: запись.name.encode("utf-8"),
        ):
            дочерний = текущий / элемент.name
            сведения = дочерний.lstat()
            текущее_свидетельство = (
                сведения.st_dev,
                сведения.st_ino,
                сведения.st_mode,
                сведения.st_size,
                сведения.st_mtime_ns,
            )
            if свидетельства.get(дочерний) != текущее_свидетельство:
                raise ОшибкаКонтракта(
                    f"Служебный объект изменился после полного preflight: {дочерний}"
                )
            if stat.S_ISDIR(сведения.st_mode):
                удалить(дочерний)
                дочерний.rmdir()
            elif stat.S_ISREG(сведения.st_mode):
                дочерний.unlink()
            else:
                raise ОшибкаКонтракта(
                    f"Служебное дерево изменило тип объекта: {дочерний}"
                )

    обследовать(путь)
    if ожидаемый_снимок is not None:
        проверить_подмножество_снимка(
            {
                "каталоги": sorted(
                    фактические_каталоги,
                    key=lambda элемент: элемент.encode("utf-8"),
                ),
                "файлы": {
                    имя: фактические_файлы[имя]
                    for имя in sorted(
                        фактические_файлы,
                        key=lambda элемент: элемент.encode("utf-8"),
                    )
                },
            },
            ожидаемый_снимок,
            назначение,
        )
    удалить(путь)
    путь.rmdir()


def прочитать_точный_обычный_файл(
    путь: Path,
    назначение: str,
    *,
    режим: int = 0o644,
) -> bytes:
    if not hasattr(os, "O_NOFOLLOW"):
        raise ОшибкаКонтракта("Платформа не предоставляет безопасное чтение файла")
    try:
        дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    except OSError as ошибка:
        raise ОшибкаКонтракта(f"Не удалось безопасно открыть {назначение}") from ошибка
    try:
        до = os.fstat(дескриптор)
        if (
            not stat.S_ISREG(до.st_mode)
            or stat.S_IMODE(до.st_mode) != режим
        ):
            raise ОшибкаКонтракта(
                f"{назначение} не является обычным файлом режима {режим:04o}"
            )
        части: list[bytes] = []
        while True:
            часть = os.read(дескриптор, 1024 * 1024)
            if not часть:
                break
            части.append(часть)
        данные = b"".join(части)
        после = os.fstat(дескриптор)
        if (
            до.st_dev != после.st_dev
            or до.st_ino != после.st_ino
            or до.st_mode != после.st_mode
            or до.st_size != после.st_size
            or до.st_mtime_ns != после.st_mtime_ns
            or len(данные) != после.st_size
        ):
            raise ОшибкаКонтракта(f"{назначение} изменён во время чтения")
        return данные
    finally:
        os.close(дескриптор)


def путь_квитанции_установки(корень: Path) -> Path:
    сырой_путь_каталога_контроля_версий = str(
        выполнить_команду_контроля_версий(
            корень,
            "rev-parse",
            "--absolute-git-dir",
        )
    ).strip()
    каталог_контроля_версий = Path(сырой_путь_каталога_контроля_версий)
    if not каталог_контроля_версий.is_absolute():
        raise ОшибкаКонтракта("Git-dir установки не является абсолютным путём")
    try:
        сведения = каталог_контроля_версий.lstat()
    except OSError as ошибка:
        raise ОшибкаКонтракта("Git-dir установки недоступен") from ошибка
    if stat.S_ISLNK(сведения.st_mode) or not stat.S_ISDIR(сведения.st_mode):
        raise ОшибкаКонтракта("Git-dir установки подменён")
    return каталог_контроля_версий / ИМЯ_КВИТАНЦИИ_УСТАНОВКИ


def проверить_устойчивый_снимок(
    значение: Any,
    назначение: str,
) -> dict[str, Any]:
    if not isinstance(значение, Mapping):
        raise ОшибкаКонтракта(f"{назначение} обязан быть объектом")
    потребовать_поля(значение, {"каталоги", "файлы"}, назначение)
    каталоги = значение["каталоги"]
    if not isinstance(каталоги, list) or not all(
        isinstance(путь, str) for путь in каталоги
    ):
        raise ОшибкаКонтракта(f"{назначение} содержит неверный список каталогов")
    for путь in каталоги:
        проверить_относительный_путь(путь, f"{назначение}.каталоги")
    if каталоги != sorted(каталоги, key=lambda путь: путь.encode("utf-8")):
        raise ОшибкаКонтракта(f"{назначение} нарушает порядок каталогов")
    if len(каталоги) != len(set(каталоги)):
        raise ОшибкаКонтракта(f"{назначение} повторяет каталог")
    файлы = значение["файлы"]
    if not isinstance(файлы, Mapping):
        raise ОшибкаКонтракта(f"{назначение} содержит неверную карту файлов")
    проверенные_файлы: dict[str, dict[str, Any]] = {}
    for путь, запись in файлы.items():
        проверить_относительный_путь(путь, f"{назначение}.файлы")
        if not isinstance(запись, Mapping):
            raise ОшибкаКонтракта(f"{назначение} содержит неверную запись файла")
        потребовать_поля(
            запись,
            {"хэш", "режим", "размер"},
            f"{назначение}.файл",
        )
        проверить_хэш(запись["хэш"], f"{назначение}.файл.хэш")
        if запись["режим"] not in {"100644", "100755"}:
            raise ОшибкаКонтракта(f"{назначение} содержит неверный режим файла")
        if type(запись["размер"]) is not int or запись["размер"] < 0:
            raise ОшибкаКонтракта(f"{назначение} содержит неверный размер файла")
        проверенные_файлы[путь] = {
            "хэш": запись["хэш"],
            "режим": запись["режим"],
            "размер": запись["размер"],
        }
    ожидаемые_каталоги: set[str] = set()
    for путь in проверенные_файлы:
        предок = PurePosixPath(путь).parent
        while предок.as_posix() != ".":
            ожидаемые_каталоги.add(предок.as_posix())
            предок = предок.parent
    if set(каталоги) != ожидаемые_каталоги:
        raise ОшибкаКонтракта(
            f"{назначение} не совпадает с родителями объявленных файлов"
        )
    if set(каталоги) & set(проверенные_файлы):
        raise ОшибкаКонтракта(f"{назначение} содержит коллизию файл–каталог")
    return {
        "каталоги": list(каталоги),
        "файлы": {
            путь: проверенные_файлы[путь]
            for путь in sorted(
                проверенные_файлы,
                key=lambda элемент: элемент.encode("utf-8"),
            )
        },
    }


def проверить_квитанцию_установки(
    значение: Any,
) -> dict[str, Any]:
    if not isinstance(значение, Mapping):
        raise ОшибкаКонтракта("Квитанция установки обязана быть объектом")
    потребовать_поля(
        значение,
        {
            "схема",
            "транзакция",
            "целевая_область",
            "служебный_каталог",
            "была_цель",
            "новый_снимок",
            "хэш_нового_дерева",
            "прежний_снимок",
            "хэш_прежнего_дерева",
        },
        "квитанция установки",
    )
    if значение["схема"] != СХЕМА_КВИТАНЦИИ_УСТАНОВКИ:
        raise ОшибкаКонтракта("Неподдержанная схема квитанции установки")
    проверить_хэш(значение["транзакция"], "квитанция.транзакция")
    if значение["целевая_область"] != ЦЕЛЕВАЯ_ОБЛАСТЬ:
        raise ОшибкаКонтракта("Квитанция объявляет чужую целевую область")
    if значение["служебный_каталог"] != СЛУЖЕБНЫЙ_КАТАЛОГ:
        raise ОшибкаКонтракта("Квитанция объявляет чужой служебный каталог")
    if type(значение["была_цель"]) is not bool:
        raise ОшибкаКонтракта("Квитанция содержит неверный признак прежней цели")
    новый_снимок = проверить_устойчивый_снимок(
        значение["новый_снимок"],
        "новый снимок квитанции",
    )
    проверить_хэш(
        значение["хэш_нового_дерева"],
        "квитанция.хэш_нового_дерева",
    )
    if хэш_дерева(новый_снимок) != значение["хэш_нового_дерева"]:
        raise ОшибкаКонтракта("Новый снимок квитанции не совпадает со своим хэшем")
    прежнее_значение = значение["прежний_снимок"]
    прежний_хэш = значение["хэш_прежнего_дерева"]
    if значение["была_цель"]:
        прежний_снимок = проверить_устойчивый_снимок(
            прежнее_значение,
            "прежний снимок квитанции",
        )
        проверить_хэш(прежний_хэш, "квитанция.хэш_прежнего_дерева")
        if хэш_дерева(прежний_снимок) != прежний_хэш:
            raise ОшибкаКонтракта(
                "Прежний снимок квитанции не совпадает со своим хэшем"
            )
    else:
        if прежнее_значение is not None or прежний_хэш is not None:
            raise ОшибкаКонтракта(
                "Квитанция первичной установки не может объявлять прежнюю цель"
            )
        прежний_снимок = None
    return {
        "схема": СХЕМА_КВИТАНЦИИ_УСТАНОВКИ,
        "транзакция": значение["транзакция"],
        "целевая_область": ЦЕЛЕВАЯ_ОБЛАСТЬ,
        "служебный_каталог": СЛУЖЕБНЫЙ_КАТАЛОГ,
        "была_цель": значение["была_цель"],
        "новый_снимок": новый_снимок,
        "хэш_нового_дерева": значение["хэш_нового_дерева"],
        "прежний_снимок": прежний_снимок,
        "хэш_прежнего_дерева": прежний_хэш,
    }


def прочитать_квитанцию_установки(
    корень: Path,
) -> tuple[Path, dict[str, Any], tuple[int, int, int, int, int]] | None:
    путь = путь_квитанции_установки(корень)
    try:
        сведения_до = путь.lstat()
    except FileNotFoundError:
        return None
    проверить_точное_имя_дочернего_пути(
        путь.parent,
        путь.name,
        "квитанции установки",
    )
    байты = прочитать_точный_обычный_файл(путь, "квитанцию установки")
    сведения_после = путь.lstat()
    свидетельство_до = (
        сведения_до.st_dev,
        сведения_до.st_ino,
        сведения_до.st_mode,
        сведения_до.st_size,
        сведения_до.st_mtime_ns,
    )
    свидетельство_после = (
        сведения_после.st_dev,
        сведения_после.st_ino,
        сведения_после.st_mode,
        сведения_после.st_size,
        сведения_после.st_mtime_ns,
    )
    if свидетельство_до != свидетельство_после:
        raise ОшибкаКонтракта("Квитанция изменилась во время чтения")
    значение = разобрать_машинные_данные(байты, "квитанция установки")
    if канонические_байты(значение) != байты:
        raise ОшибкаКонтракта("Квитанция установки имеет неканонические байты")
    return путь, проверить_квитанцию_установки(значение), свидетельство_после


def проверить_неизменность_квитанции(
    корень: Path,
    ожидаемая: Mapping[str, Any],
    свидетельство: tuple[int, int, int, int, int],
) -> None:
    прочитанная = прочитать_квитанцию_установки(корень)
    if прочитанная is None:
        raise ОшибкаКонтракта("Квитанция установки исчезла")
    _путь, значение, текущее_свидетельство = прочитанная
    if (
        канонические_байты(значение) != канонические_байты(ожидаемая)
        or текущее_свидетельство != свидетельство
    ):
        raise ОшибкаКонтракта("Квитанция установки была подменена")


def записать_квитанцию_установки(
    корень: Path,
    квитанция: Mapping[str, Any],
) -> Path:
    проверенная = проверить_квитанцию_установки(квитанция)
    путь = путь_квитанции_установки(корень)
    временный = путь.with_name(
        f"{путь.name}.{проверенная['транзакция'].removeprefix('sha256:')}.tmp"
    )
    try:
        путь.lstat()
    except FileNotFoundError:
        pass
    else:
        raise ОшибкаКонтракта("Незавершённая квитанция установки уже существует")
    try:
        временный.lstat()
    except FileNotFoundError:
        pass
    else:
        проверить_точное_имя_дочернего_пути(
            временный.parent,
            временный.name,
            "временной квитанции установки",
        )
        raise ОшибкаКонтракта(
            "Временная квитанция установки уже существует"
        )
    созданное_свидетельство: tuple[int, int, int, int, int] | None = None
    try:
        записать_обычный_файл(
            временный,
            канонические_байты(проверенная),
            "100644",
        )
        проверить_точное_имя_дочернего_пути(
            временный.parent,
            временный.name,
            "записанной временной квитанции установки",
        )
        сведения_временного = временный.lstat()
        созданное_свидетельство = (
            сведения_временного.st_dev,
            сведения_временного.st_ino,
            сведения_временного.st_mode,
            сведения_временного.st_size,
            сведения_временного.st_mtime_ns,
        )
        потребовать_отсутствие_пути(
            путь,
            "Назначение публикуемой квитанции установки",
        )
        атомарно_переименовать_без_замены(временный, путь)
        синхронизировать_каталог(путь.parent)
    except Exception:
        if созданное_свидетельство is not None:
            try:
                текущие = временный.lstat()
            except FileNotFoundError:
                pass
            else:
                if созданное_свидетельство == (
                    текущие.st_dev,
                    текущие.st_ino,
                    текущие.st_mode,
                    текущие.st_size,
                    текущие.st_mtime_ns,
                ):
                    временный.unlink()
        raise
    return путь


def удалить_квитанцию_установки(
    корень: Path,
    ожидаемая: Mapping[str, Any],
    ожидаемое_свидетельство: tuple[int, int, int, int, int] | None = None,
) -> None:
    прочитанная = прочитать_квитанцию_установки(корень)
    if прочитанная is None:
        raise ОшибкаКонтракта("Квитанция установки исчезла перед очисткой")
    путь, значение, свидетельство = прочитанная
    if (
        канонические_байты(значение) != канонические_байты(ожидаемая)
        or (
            ожидаемое_свидетельство is not None
            and свидетельство != ожидаемое_свидетельство
        )
    ):
        raise ОшибкаКонтракта("Квитанция установки изменилась перед очисткой")
    путь.unlink()
    синхронизировать_каталог(путь.parent)


def проверить_состояние_установки(
    значение: Any,
    квитанция: Mapping[str, Any],
) -> dict[str, Any]:
    if not isinstance(значение, Mapping):
        raise ОшибкаКонтракта("Журнал установки обязан быть объектом")
    потребовать_поля(
        значение,
        {
            "схема",
            "транзакция",
            "фаза",
            "была_цель",
            "хэш_нового_дерева",
            "хэш_прежнего_дерева",
        },
        "журнал установки",
    )
    if значение["схема"] != СХЕМА_УСТАНОВКИ:
        raise ОшибкаКонтракта("Неподдержанная схема журнала установки")
    if значение["транзакция"] != квитанция["транзакция"]:
        raise ОшибкаКонтракта("Журнал не принадлежит активной квитанции установки")
    if значение["фаза"] not in {
        "строится",
        "подготовлено",
        "прежнее_зарезервировано",
        "новое_установлено",
        "принято",
        "откачено",
    }:
        raise ОшибкаКонтракта("Неизвестная фаза журнала установки")
    for поле in (
        "была_цель",
        "хэш_нового_дерева",
        "хэш_прежнего_дерева",
    ):
        if канонические_байты(значение[поле]) != канонические_байты(
            квитанция[поле]
        ):
            raise ОшибкаКонтракта(
                f"Журнал установки расходится с квитанцией: {поле}"
            )
    return dict(значение)


def прочитать_состояние_установки(
    путь: Path,
    квитанция: Mapping[str, Any],
    назначение: str,
) -> dict[str, Any]:
    байты = прочитать_точный_обычный_файл(путь, назначение)
    значение = разобрать_машинные_данные(байты, назначение)
    if канонические_байты(значение) != байты:
        raise ОшибкаКонтракта(f"{назначение} имеет неканонические байты")
    return проверить_состояние_установки(значение, квитанция)


def сформировать_ожидаемый_снимок_поколения(
    план: Mapping[str, Any],
    выходы: Mapping[str, bytes],
    манифест: Mapping[str, Any],
) -> dict[str, Any]:
    режимы = {
        запись["целевой_путь"]: запись["режим"]
        for запись in план["записи"]
    }
    файлы: dict[str, dict[str, Any]] = {}
    for полный_путь, данные in выходы.items():
        if not isinstance(данные, bytes) or полный_путь not in режимы:
            raise ОшибкаКонтракта("Нельзя доказать ожидаемый снимок поколения")
        относительный = (
            PurePosixPath(полный_путь)
            .relative_to(PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ))
            .as_posix()
        )
        файлы[относительный] = {
            "хэш": хэш_байтов(данные),
            "режим": режимы[полный_путь],
            "размер": len(данные),
        }
    байты_манифеста = канонические_байты(манифест)
    файлы[PurePosixPath(ПУТЬ_МАНИФЕСТА).name] = {
        "хэш": хэш_байтов(байты_манифеста),
        "режим": "100644",
        "размер": len(байты_манифеста),
    }
    каталоги: set[str] = set()
    for путь in файлы:
        предок = PurePosixPath(путь).parent
        while предок.as_posix() != ".":
            каталоги.add(предок.as_posix())
            предок = предок.parent
    return проверить_устойчивый_снимок(
        {
            "каталоги": sorted(
                каталоги,
                key=lambda путь: путь.encode("utf-8"),
            ),
            "файлы": файлы,
        },
        "ожидаемый снимок поколения",
    )


def снять_служебный_снимок_если_есть(
    корень: Path,
    путь: Path,
    *,
    допустимые_режимы_корня: frozenset[int] = frozenset({0o755}),
) -> dict[str, Any] | None:
    try:
        путь.lstat()
    except FileNotFoundError:
        return None
    снимок = снимок_целевого_дерева(
        корень,
        путь,
        допустимые_режимы_корня=допустимые_режимы_корня,
    )
    return устойчивый_снимок_дерева(снимок)


def проверить_подмножество_снимка(
    фактический: Mapping[str, Any],
    ожидаемый: Mapping[str, Any],
    назначение: str,
    *,
    полный: bool = False,
) -> None:
    фактические_каталоги = set(фактический["каталоги"])
    ожидаемые_каталоги = set(ожидаемый["каталоги"])
    фактические_файлы = фактический["файлы"]
    ожидаемые_файлы = ожидаемый["файлы"]
    if not фактические_каталоги <= ожидаемые_каталоги:
        raise ОшибкаКонтракта(f"{назначение} содержит неизвестный каталог")
    if not set(фактические_файлы) <= set(ожидаемые_файлы):
        raise ОшибкаКонтракта(f"{назначение} содержит неизвестный файл")
    for путь, запись in фактические_файлы.items():
        if канонические_байты(запись) != канонические_байты(
            ожидаемые_файлы[путь]
        ):
            raise ОшибкаКонтракта(f"{назначение} изменил управляемый файл: {путь}")
    if полный and канонические_байты(фактический) != канонические_байты(
        ожидаемый
    ):
        raise ОшибкаКонтракта(f"{назначение} не совпадает с полным снимком")


def классифицировать_фактическую_цель(
    корень: Path,
    цель: Path,
    квитанция: Mapping[str, Any],
) -> tuple[str, dict[str, Any] | None]:
    снимок = снять_служебный_снимок_если_есть(корень, цель)
    if снимок is None:
        return "отсутствует", None
    if канонические_байты(снимок) == канонические_байты(
        квитанция["новый_снимок"]
    ):
        return "новая", снимок
    прежний = квитанция["прежний_снимок"]
    if прежний is not None and канонические_байты(снимок) == канонические_байты(
        прежний
    ):
        return "прежняя", снимок
    raise ОшибкаКонтракта("Фактическая цель не принадлежит квитанции установки")



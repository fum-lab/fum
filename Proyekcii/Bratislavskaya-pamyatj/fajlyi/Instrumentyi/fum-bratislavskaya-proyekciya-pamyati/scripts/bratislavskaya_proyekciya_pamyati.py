def каноническое_содержание_разметки(текст: str) -> str:
    return текст if текст.endswith("\n") else текст + "\n"


def разделить_свежесть(текст: str, путь: str) -> tuple[str, str | None]:
    совпадение = БЛОК_СВЕЖЕСТИ.search(текст)
    if совпадение is None:
        if НАЧАЛО_СВЕЖЕСТИ in текст or КОНЕЦ_СВЕЖЕСТИ in текст:
            raise ОшибкаКонтракта(
                f"Повреждён служебный блок FUM-MD-RECENCY: {путь}"
            )
        return текст, None
    содержание = текст[: совпадение.start()] + текст[совпадение.end() :]
    каноническое_содержание = каноническое_содержание_разметки(содержание)
    ожидаемые_хэши = {
        hashlib.sha256(каноническое_содержание.encode("utf-8")).hexdigest(),
        hashlib.sha256(
            стабильное_содержание_для_свежести(
                путь,
                каноническое_содержание,
            ).encode("utf-8")
        ).hexdigest(),
    }
    if совпадение.group("хэш") not in ожидаемые_хэши:
        raise ОшибкаКонтракта(
            f"Исходная FUM-MD-RECENCY метка не совпадает с содержанием: {путь}"
        )
    return каноническое_содержание, совпадение.group("время")


def стабильное_содержание_для_свежести(путь: str, содержание: str) -> str:
    части = PurePosixPath(путь).parts
    if len(части) == 3 and части[0] == "Журнал" and части[-1] == "отчёт.md":
        число_начал = содержание.count("<!-- FUM-CHECK-RUNS:BEGIN ")
        число_концов = содержание.count("<!-- FUM-CHECK-RUNS:END -->")
        if число_начал or число_концов:
            совпадение = УПРАВЛЯЕМЫЙ_БЛОК_ПРОВЕРОК.search(содержание)
            if число_начал != 1 or число_концов != 1 or совпадение is None:
                raise ОшибкаКонтракта(
                    f"Повреждён управляемый блок запусков в отчёте: {путь}"
                )
            содержание = (
                содержание[: совпадение.start()]
                + ЗАМЕСТИТЕЛЬ_БЛОКА_ПРОВЕРОК
                + содержание[совпадение.end() :]
            )
    return каноническое_содержание_разметки(содержание)


def присоединить_свежесть(путь: str, содержание: str, время: str | None) -> str:
    if время is None:
        return содержание
    стабильное = стабильное_содержание_для_свежести(путь, содержание)
    хэш = hashlib.sha256(стабильное.encode("utf-8")).hexdigest()
    блок = "\n".join(
        [
            НАЧАЛО_СВЕЖЕСТИ,
            f"<!-- last-content-edit: {время} -->",
            f"<!-- content-sha256: sha256:{хэш} -->",
            КОНЕЦ_СВЕЖЕСТИ,
            "",
        ]
    )
    return f"{каноническое_содержание_разметки(содержание)}\n{блок}"


def канонические_байты(значение: Any) -> bytes:
    try:
        return (
            json.dumps(
                значение,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
                allow_nan=False,
            )
            + "\n"
        ).encode("utf-8")
    except (TypeError, ValueError, UnicodeError) as ошибка:
        raise ОшибкаКонтракта(
            f"Значение нельзя представить каноническим JSON: {ошибка}"
        ) from ошибка


def хэш_байтов(данные: bytes) -> str:
    return f"sha256:{hashlib.sha256(данные).hexdigest()}"


def хэш_значения(значение: Any) -> str:
    return хэш_байтов(канонические_байты(значение))


def пары_без_повторов(пары: list[tuple[str, Any]]) -> dict[str, Any]:
    результат: dict[str, Any] = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ОшибкаКонтракта(f"JSON содержит повторное поле: {ключ}")
        результат[ключ] = значение
    return результат


def отклонить_нестандартное_число(значение: str) -> None:
    raise ОшибкаКонтракта(f"JSON содержит нестандартное числовое значение: {значение}")


def загрузить_машинные_данные(путь: Path, назначение: str) -> Any:
    try:
        данные = путь.read_bytes()
        return разобрать_машинные_данные(данные, f"{назначение} {путь}")
    except ОшибкаКонтракта:
        raise
    except OSError as ошибка:
        raise ОшибкаКонтракта(
            f"Не удалось прочитать {назначение} {путь}: {ошибка}"
        ) from ошибка


def разобрать_машинные_данные(данные: bytes, назначение: str) -> Any:
    try:
        return json.loads(
            данные.decode("utf-8"),
            object_pairs_hook=пары_без_повторов,
            parse_constant=отклонить_нестандартное_число,
        )
    except ОшибкаКонтракта:
        raise
    except (UnicodeError, json.JSONDecodeError) as ошибка:
        raise ОшибкаКонтракта(
            f"Не удалось разобрать {назначение}: {ошибка}"
        ) from ошибка


def проверить_относительный_путь(
    значение: Any,
    поле: str,
    *,
    разрешить_точку: bool = False,
) -> str:
    if not isinstance(значение, str) or not значение:
        raise ОшибкаКонтракта(f"{поле}: требуется непустой относительный путь")
    if значение == "." and разрешить_точку:
        return значение
    if значение.startswith("/") or "\\" in значение:
        raise ОшибкаКонтракта(f"{поле}: требуется относительный POSIX-путь")
    части = значение.split("/")
    if any(часть in {"", ".", ".."} or "\0" in часть for часть in части):
        raise ОшибкаКонтракта(f"{поле}: запрещён небезопасный компонент")
    return значение


def путь_под_префиксом(путь: str, префикс: str) -> bool:
    return путь == префикс or путь.startswith(префикс + "/")


def проверить_точное_имя_дочернего_пути(
    родитель: Path,
    имя: str,
    назначение: str,
) -> None:
    try:
        имена = {элемент.name for элемент in os.scandir(родитель)}
    except OSError as ошибка:
        raise ОшибкаКонтракта(
            f"Не удалось проверить точное имя { назначение }"
        ) from ошибка
    if имя not in имена:
        raise ОшибкаКонтракта(
            f"Фактическое имя { назначение } не совпадает с контрактом: { имя }"
        )


def потребовать_поля(
    значение: Mapping[str, Any],
    ожидаемые: set[str],
    назначение: str,
) -> None:
    поля = set(значение)
    if поля != ожидаемые:
        raise ОшибкаКонтракта(
            f"{назначение}: нарушен закрытый набор полей; "
            f"отсутствуют={sorted(ожидаемые - поля)}, лишние={sorted(поля - ожидаемые)}"
        )


def проверить_массив_строк(значение: Any, поле: str) -> list[str]:
    if not isinstance(значение, list) or not значение or not all(
        isinstance(элемент, str) and элемент for элемент in значение
    ):
        raise ОшибкаКонтракта(f"{поле}: требуется массив непустых строк")
    if len(значение) != len(set(значение)):
        raise ОшибкаКонтракта(f"{поле}: повторные значения запрещены")
    return list(значение)


def проверить_форматы(форматы: Any) -> None:
    if not isinstance(форматы, Mapping):
        raise ОшибкаКонтракта("форматы: требуется объект")
    классы = {
        "разметка",
        "разметка_с_дословным_блоком",
        "дословные_источники",
        "код",
        "машинные_данные",
        "прочие_точные_форматы",
        "машинные_шаблоны",
        "двоичные_и_нетекстовые",
    }
    потребовать_поля(форматы, классы, "форматы")

    разметка = форматы["разметка"]
    if not isinstance(разметка, Mapping):
        raise ОшибкаКонтракта("форматы.разметка: требуется объект")
    потребовать_поля(
        разметка,
        {
            "расширения",
            "действие",
            "локальные_ссылки",
            "исключённые_локальные_цели",
            "якоря",
            "внешние_адреса",
            "FUM-MD-RECENCY",
        },
        "форматы.разметка",
    )
    проверить_массив_строк(разметка["расширения"], "форматы.разметка.расширения")
    ожидаемая_разметка = {
        "действие": "преобразовать_структурно",
        "локальные_ссылки": "перенаправить_в_поколение",
        "исключённые_локальные_цели": "сохранить_ссылку_на_канонический_слой",
        "якоря": "преобразовать_и_проверить",
        "внешние_адреса": "сохранить",
        "FUM-MD-RECENCY": "пересчитать_без_изменения_last-content-edit",
    }
    for поле, ожидаемое in ожидаемая_разметка.items():
        if разметка.get(поле) != ожидаемое:
            raise ОшибкаКонтракта(
                f"форматы.разметка.{поле}: ожидается {ожидаемое!r}"
            )

    запрос = форматы["разметка_с_дословным_блоком"]
    if not isinstance(запрос, Mapping):
        raise ОшибкаКонтракта("форматы.разметка_с_дословным_блоком: требуется объект")
    потребовать_поля(
        запрос,
        {"шаблоны", "заголовок_начала", "действие"},
        "форматы.разметка_с_дословным_блоком",
    )
    проверить_массив_строк(
        запрос["шаблоны"],
        "форматы.разметка_с_дословным_блоком.шаблоны",
    )
    if запрос["заголовок_начала"] != "## Текст запроса":
        raise ОшибкаКонтракта("Дословным может быть только блок '## Текст запроса'")
    if запрос["действие"] != "преобразовать_разметку_с_дословным_блоком":
        raise ОшибкаКонтракта("Весь запрос.md нельзя сохранять побайтово")

    простые = {
        "дословные_источники": ("шаблоны",),
        "код": ("расширения",),
        "машинные_данные": ("расширения",),
        "машинные_шаблоны": ("окончания",),
    }
    for имя, поля_массивов in простые.items():
        раздел = форматы[имя]
        if not isinstance(раздел, Mapping):
            raise ОшибкаКонтракта(f"форматы.{имя}: требуется объект")
        потребовать_поля(раздел, {*поля_массивов, "действие"}, f"форматы.{имя}")
        for поле in поля_массивов:
            проверить_массив_строк(раздел[поле], f"форматы.{имя}.{поле}")
        if раздел["действие"] != "сохранить_байты":
            raise ОшибкаКонтракта(f"форматы.{имя}: версия 2 сохраняет байты")

    прочие = форматы["прочие_точные_форматы"]
    if not isinstance(прочие, Mapping):
        raise ОшибкаКонтракта("форматы.прочие_точные_форматы: требуется объект")
    потребовать_поля(
        прочие,
        {"расширения", "точные_пути", "действие"},
        "форматы.прочие_точные_форматы",
    )
    проверить_массив_строк(
        прочие["расширения"],
        "форматы.прочие_точные_форматы.расширения",
    )
    проверить_массив_строк(
        прочие["точные_пути"],
        "форматы.прочие_точные_форматы.точные_пути",
    )
    if прочие["действие"] != "сохранить_байты":
        raise ОшибкаКонтракта("Прочие точные форматы обязаны сохранять байты")

    двоичные = форматы["двоичные_и_нетекстовые"]
    if not isinstance(двоичные, Mapping):
        raise ОшибкаКонтракта("форматы.двоичные_и_нетекстовые: требуется объект")
    потребовать_поля(двоичные, {"действие"}, "форматы.двоичные_и_нетекстовые")
    if двоичные["действие"] != "сохранить_байты":
        raise ОшибкаКонтракта("Двоичные и не-UTF-8 файлы обязаны сохранять байты")

    точные_списки = {
        ("разметка", "расширения"): [".md"],
        ("разметка_с_дословным_блоком", "шаблоны"): ["Журнал/*/запрос.md"],
        ("дословные_источники", "шаблоны"): ["Источники/**"],
        ("код", "расширения"): [".py", ".swift", ".sh"],
        ("машинные_данные", "расширения"): [
            ".json",
            ".jsonl",
            ".toml",
            ".yaml",
            ".yml",
            ".canvas",
            ".lock",
        ],
        ("прочие_точные_форматы", "расширения"): [
            ".txt",
            ".html",
            ".base64",
            ".mlir",
            ".css",
        ],
        ("прочие_точные_форматы", "точные_пути"): [
            ".gitignore",
            ".gitmodules",
            ".obsidian/fum-recency-reference-date",
            "LICENSE",
            "fum",
            "ЛИЦЕНЗИЯ",
        ],
        ("машинные_шаблоны", "окончания"): [".md.шаблон"],
    }
    for (раздел, поле), ожидаемое in точные_списки.items():
        if форматы[раздел][поле] != ожидаемое:
            raise ОшибкаКонтракта(
                f"форматы.{раздел}.{поле}: exact список версии 2 изменён"
            )


def проверить_политику(политика: Mapping[str, Any]) -> dict[str, Any]:
    if not isinstance(политика, Mapping):
        raise ОшибкаКонтракта("Контракт обязан быть JSON-объектом")
    поля = {
        "схема",
        "исходная_область",
        "производное_пространство",
        "целевая_область",
        "корень_файлов",
        "путь_манифеста",
        "исключённые_префиксы",
        "структурные_исключения",
        "исключённая_ссылка_на_репозиторий",
        "преобразование",
        "форматы",
        "ограничения_пути",
        "сохраняемые_технические_расширения",
        "пустые_каталоги",
    }
    потребовать_поля(политика, поля, "контракт")
    if политика["схема"] == "fum.политика-братиславской-проекции.1":
        raise ОшибкаКонтракта(
            "Контракт версии 1 неизменяем; требуется явная миграция v1 → v2"
        )
    if политика["схема"] != СХЕМА_ПОЛИТИКИ:
        raise ОшибкаКонтракта("Неподдержанная схема контракта")
    if проверить_относительный_путь(
        политика["исходная_область"],
        "исходная_область",
        разрешить_точку=True,
    ) != ".":
        raise ОшибкаКонтракта("Версия 2 поддерживает полный инвентарь только от корня '.'")

    ожидаемые_пути = {
        "производное_пространство": ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
        "целевая_область": ЦЕЛЕВАЯ_ОБЛАСТЬ,
        "корень_файлов": КОРЕНЬ_ФАЙЛОВ,
        "путь_манифеста": ПУТЬ_МАНИФЕСТА,
    }
    for поле, ожидаемое in ожидаемые_пути.items():
        if политика[поле] != ожидаемое:
            raise ОшибкаКонтракта(
                f"{поле}: закреплено точное непересекающееся значение {ожидаемое!r}"
            )
        проверить_относительный_путь(политика[поле], поле)
    if путь_под_префиксом(ПУТЬ_МАНИФЕСТА, КОРЕНЬ_ФАЙЛОВ):
        raise ОшибкаКонтракта("Манифест пересекается с деревом файлов")

    префиксы = проверить_массив_строк(
        политика["исключённые_префиксы"],
        "исключённые_префиксы",
    )
    if префиксы != [".git", "Подузлы", ПРОИЗВОДНОЕ_ПРОСТРАНСТВО]:
        raise ОшибкаКонтракта("Нельзя расширять точные исключённые префиксы версии 2")

    структурные = политика["структурные_исключения"]
    if not isinstance(структурные, Mapping):
        raise ОшибкаКонтракта("структурные_исключения: требуется объект")
    потребовать_поля(
        структурные,
        {"имена_каталогов", "окончания_каталогов", "пути"},
        "структурные_исключения",
    )
    ожидаемые_структурные = {
        "имена_каталогов": [
            ".build",
            ".swiftpm",
            ".cache",
            "cache",
            "caches",
            "__pycache__",
            ".pytest_cache",
            ".mypy_cache",
            ".ruff_cache",
        ],
        "окончания_каталогов": ["-cache", "_cache", ".cache"],
        "пути": list(ТОЧНЫЕ_СТРУКТУРНЫЕ_ИСКЛЮЧЁННЫЕ_ПУТИ),
    }
    for поле, ожидаемое in ожидаемые_структурные.items():
        фактическое = проверить_массив_строк(
            структурные[поле],
            f"структурные_исключения.{поле}",
        )
        if фактическое != ожидаемое:
            raise ОшибкаКонтракта(
                f"структурные_исключения.{поле}: exact список версии 2 изменён"
            )

    ссылка_зависимости = политика["исключённая_ссылка_на_репозиторий"]
    if not isinstance(ссылка_зависимости, Mapping):
        raise ОшибкаКонтракта("исключённая_ссылка_на_репозиторий: требуется объект")
    потребовать_поля(
        ссылка_зависимости,
        {"путь", "OID"},
        "исключённая_ссылка_на_репозиторий",
    )
    if ссылка_зависимости != {
        "путь": ПУТЬ_ЗАВИСИМОСТИ,
        "OID": РЕВИЗИЯ_ЗАВИСИМОСТИ,
    }:
        raise ОшибкаКонтракта("Допускается только exact gitlink закреплённого LinguisticKit")

    преобразование = политика["преобразование"]
    ожидаемое_преобразование = {
        "ревизия": РЕВИЗИЯ_ЗАВИСИМОСТИ,
        "исходная_письменность": "Cyrl",
        "целевая_письменность": "Latn",
        "таблица": "ru",
        "метод": "applyingTransform",
    }
    if not isinstance(преобразование, Mapping) or dict(преобразование) != ожидаемое_преобразование:
        raise ОшибкаКонтракта("Контракт LinguisticKit или ревизия не совпадают")
    проверить_форматы(политика["форматы"])

    ограничения = политика["ограничения_пути"]
    if not isinstance(ограничения, Mapping):
        raise ОшибкаКонтракта("ограничения_пути: требуется объект")
    потребовать_поля(
        ограничения,
        {
            "максимум_байтов_компонента",
            "максимум_кодовых_единиц_UTF_16_компонента",
            "максимум_байтов_пути",
            "зарезервированные_системные_имена",
        },
        "ограничения_пути",
    )
    for поле in (
        "максимум_байтов_компонента",
        "максимум_кодовых_единиц_UTF_16_компонента",
        "максимум_байтов_пути",
    ):
        if (
            isinstance(ограничения[поле], bool)
            or not isinstance(ограничения[поле], int)
            or ограничения[поле] <= 0
        ):
            raise ОшибкаКонтракта(f"ограничения_пути.{поле}: требуется положительное число")
    if ограничения["максимум_байтов_компонента"] > 255:
        raise ОшибкаКонтракта("Лимит компонента не может превышать 255 UTF-8 байт")
    if ограничения["максимум_кодовых_единиц_UTF_16_компонента"] > 255:
        raise ОшибкаКонтракта("Лимит компонента не может превышать 255 единиц UTF-16")
    if проверить_массив_строк(
        ограничения["зарезервированные_системные_имена"],
        "зарезервированные_системные_имена",
    ) != ["CON", "PRN", "AUX", "NUL", "CLOCK$", "CONIN$", "CONOUT$"]:
        raise ОшибкаКонтракта("Список системных имён Windows версии 2 изменён")

    расширения = проверить_массив_строк(
        политика["сохраняемые_технические_расширения"],
        "сохраняемые_технические_расширения",
    )
    if not all(расширение.startswith(".") for расширение in расширения):
        raise ОшибкаКонтракта("Технические расширения обязаны начинаться с точки")
    ожидаемые_расширения = [
        ".md",
        ".json",
        ".jsonl",
        ".toml",
        ".yaml",
        ".yml",
        ".swift",
        ".py",
        ".sh",
        ".txt",
        ".html",
        ".base64",
        ".mlir",
        ".css",
        ".canvas",
        ".lock",
        ".bin",
    ]
    if расширения != ожидаемые_расширения:
        raise ОшибкаКонтракта(
            "сохраняемые_технические_расширения: exact список версии 2 изменён"
        )
    if политика["пустые_каталоги"] != "не_включаются_в_инвентарь_репозитория":
        raise ОшибкаКонтракта("Пустые каталоги не входят в Git-инвентарь версии 2")
    return dict(политика)


def загрузить_политику(путь: Path) -> dict[str, Any]:
    return проверить_политику(загрузить_машинные_данные(путь, "контракт"))


def окружение_команды_контроля_версий() -> dict[str, str]:
    окружение = {
        ключ: значение
        for ключ, значение in os.environ.items()
        if not ключ.startswith("GIT_")
    }
    окружение["GIT_NO_REPLACE_OBJECTS"] = "1"
    окружение["GIT_OPTIONAL_LOCKS"] = "0"
    return окружение


def выполнить_команду_контроля_версий(
    корень: Path,
    *аргументы: str,
    двоичный: bool = False,
) -> bytes | str:
    try:
        результат = subprocess.run(
            ["git", "-C", str(корень), *аргументы],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=not двоичный,
            env=окружение_команды_контроля_версий(),
        )
    except (OSError, subprocess.CalledProcessError) as ошибка:
        пояснение = getattr(ошибка, "stderr", None)
        if isinstance(пояснение, bytes):
            пояснение = пояснение.decode("utf-8", errors="replace")
        raise ОшибкаКонтракта(
            f"Git-инвентарь недоступен: {(пояснение or str(ошибка)).strip()}"
        ) from ошибка
    return результат.stdout


def прочитать_индекс(корень: Path) -> dict[str, dict[str, str]]:
    сырые_данные = выполнить_команду_контроля_версий(
        корень,
        "ls-files",
        "-s",
        "-z",
        двоичный=True,
    )
    assert isinstance(сырые_данные, bytes)
    записи: dict[str, dict[str, str]] = {}
    for сырая_запись in сырые_данные.split(b"\0"):
        if not сырая_запись:
            continue
        try:
            заголовок, сырой_путь = сырая_запись.split(b"\t", 1)
            режим, объект, стадия = заголовок.decode("ascii").split(" ")
            путь = сырой_путь.decode("utf-8")
        except (ValueError, UnicodeError) as ошибка:
            raise ОшибкаКонтракта(
                "Git-индекс содержит неподдержанное имя или запись"
            ) from ошибка
        проверить_относительный_путь(путь, "путь Git-индекса")
        if путь_под_префиксом(путь, ПРОИЗВОДНОЕ_ПРОСТРАНСТВО):
            continue
        if стадия != "0":
            raise ОшибкаКонтракта(f"Git-индекс содержит конфликтную запись: {путь}")
        if путь in записи:
            raise ОшибкаКонтракта(f"Git-индекс повторяет путь: {путь}")
        записи[путь] = {
            "режим": режим,
            "идентификатор_объекта_репозитория": объект,
        }
    return записи


def прочитать_стадии_индекса_проекции(
    корень: Path,
) -> dict[str, dict[str, dict[str, str]]]:
    сырые_данные = выполнить_команду_контроля_версий(
        корень,
        "ls-files",
        "--stage",
        "-z",
        двоичный=True,
    )
    assert isinstance(сырые_данные, bytes)
    записи: dict[str, dict[str, dict[str, str]]] = {}
    for сырая_запись in сырые_данные.split(b"\0"):
        if not сырая_запись:
            continue
        try:
            заголовок, сырой_путь = сырая_запись.split(b"\t", 1)
            режим, объект, стадия = заголовок.decode("ascii").split(" ")
            путь = сырой_путь.decode("utf-8")
        except (ValueError, UnicodeError) as ошибка:
            raise ОшибкаКонтракта(
                "Git-индекс содержит неподдержанную запись проекции"
            ) from ошибка
        проверить_относительный_путь(путь, "путь Git-индекса")
        if not путь_под_префиксом(путь, ПРОИЗВОДНОЕ_ПРОСТРАНСТВО):
            continue
        стадии = записи.setdefault(путь, {})
        if стадия in стадии:
            raise ОшибкаКонтракта(
                f"Git-индекс повторяет стадию проекции: {путь}, {стадия}"
            )
        стадии[стадия] = {
            "режим": режим,
            "идентификатор_объекта_репозитория": объект,
        }
    return записи


def конфликтные_пути_проекции(корень: Path) -> set[str]:
    return {
        путь
        for путь, стадии in прочитать_стадии_индекса_проекции(корень).items()
        if any(стадия != "0" for стадия in стадии)
    }


def прочитать_дерево_проекции_ревизии(
    корень: Path,
    ревизия: str,
) -> dict[str, dict[str, str]]:
    сырые_данные = выполнить_команду_контроля_версий(
        корень,
        "ls-tree",
        "-r",
        "-z",
        "--full-tree",
        ревизия,
        "--",
        ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
        двоичный=True,
    )
    assert isinstance(сырые_данные, bytes)
    записи: dict[str, dict[str, str]] = {}
    for сырая_запись in сырые_данные.split(b"\0"):
        if not сырая_запись:
            continue
        try:
            заголовок, сырой_путь = сырая_запись.split(b"\t", 1)
            режим, тип, объект = заголовок.decode("ascii").split(" ")
            путь = сырой_путь.decode("utf-8")
        except (ValueError, UnicodeError) as ошибка:
            raise ОшибкаКонтракта(
                "Git-дерево слияния содержит неподдерживаемую запись"
            ) from ошибка
        проверить_относительный_путь(путь, "путь Git-дерева слияния")
        if тип != "blob" or режим not in {"100644", "100755"}:
            raise ОшибкаКонтракта(
                f"Git-дерево слияния содержит необычный объект: {путь}"
            )
        if путь in записи:
            raise ОшибкаКонтракта(f"Git-дерево повторяет путь: {путь}")
        записи[путь] = {
            "режим": режим,
            "идентификатор_объекта_репозитория": объект,
        }
    return записи


def проверить_происхождение_стадий_слияния(
    корень: Path,
    стадии_индекса: Mapping[str, Mapping[str, Mapping[str, str]]],
) -> None:
    try:
        текущая = str(
            выполнить_команду_контроля_версий(корень, "rev-parse", "--verify", "HEAD")
        ).strip()
        другая = str(
            выполнить_команду_контроля_версий(корень, "rev-parse", "--verify", "MERGE_HEAD")
        ).strip()
    except ОшибкаКонтракта as ошибка:
        raise ОшибкаКонтракта(
            "Конфликтные стадии проекции не подтверждены "
            "активной операцией слияния"
        ) from ошибка
    основы = [
        строка
        for строка in str(
            выполнить_команду_контроля_версий(
                корень, "merge-base", "--all", текущая, другая
            )
        ).splitlines()
        if строка
    ]
    if len(основы) != 1:
        raise ОшибкаКонтракта(
            "Конфликтная проекция требует ровно одну доказанную основу слияния"
        )
    деревья = {
        "1": прочитать_дерево_проекции_ревизии(корень, основы[0]),
        "2": прочитать_дерево_проекции_ревизии(корень, текущая),
        "3": прочитать_дерево_проекции_ревизии(корень, другая),
    }
    for путь, стадии in стадии_индекса.items():
        for стадия, запись in стадии.items():
            if стадия == "0":
                continue
            if стадия not in деревья or деревья[стадия].get(путь) != запись:
                raise ОшибкаКонтракта(
                    "Конфликтная стадия не совпадает с доказанным "
                    f"Git-деревом: {путь}, стадия {стадия}"
                )


def снимок_границы_конфликтной_проекции(
    корень: Path,
) -> dict[str, Any]:
    стадии = прочитать_стадии_индекса_проекции(корень)
    if not any(
        стадия != "0"
        for записи_пути in стадии.values()
        for стадия in записи_пути
    ):
        raise ОшибкаКонтракта(
            "Граница конфликтной проекции потеряла конфликтные стадии"
        )
    проверить_происхождение_стадий_слияния(корень, стадии)
    ссылки: dict[str, str] = {}
    for имя, ревизия in (
        ("HEAD", "HEAD"),
        ("MERGE_HEAD", "MERGE_HEAD"),
        ("AUTO_MERGE", "AUTO_MERGE^{tree}"),
    ):
        ссылки[имя] = str(
            выполнить_команду_контроля_версий(
                корень,
                "rev-parse",
                "--verify",
                ревизия,
            )
        ).strip()
    return {
        "стадии": копия_машинного_значения(стадии),
        "ссылки": ссылки,
    }


def проверить_неизменность_рабочих_конфликтов(
    корень: Path,
    снимок: Mapping[str, Any],
) -> None:
    try:
        автослияние = str(
            выполнить_команду_контроля_версий(
                корень, "rev-parse", "--verify", "AUTO_MERGE^{tree}"
            )
        ).strip()
    except ОшибкаКонтракта as ошибка:
        raise ОшибкаКонтракта(
            "Рабочее конфликтное поколение не имеет доказанного AUTO_MERGE"
        ) from ошибка
    дерево = прочитать_дерево_проекции_ревизии(корень, автослияние)
    ожидаемые = {
        путь: запись
        for путь, запись in дерево.items()
        if путь_под_префиксом(путь, ЦЕЛЕВАЯ_ОБЛАСТЬ)
    }
    фактические = {
        (PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ) / PurePosixPath(путь)).as_posix(): запись
        for путь, запись in снимок["файлы"].items()
    }
    if set(фактические) != set(ожидаемые):
        raise ОшибкаКонтракта(
            "Рабочее конфликтное поколение изменило состав относительно AUTO_MERGE"
        )
    for путь, ожидаемая in ожидаемые.items():
        байты = выполнить_команду_контроля_версий(
            корень,
            "cat-file",
            "blob",
            ожидаемая["идентификатор_объекта_репозитория"],
            двоичный=True,
        )
        assert isinstance(байты, bytes)
        фактическая = фактические[путь]
        if (фактическая["режим"] != ожидаемая["режим"] or фактическая["хэш"] != хэш_байтов(байты)):
            raise ОшибкаКонтракта(
                f"Рабочее конфликтное поколение изменено вручную: {путь}"
            )


def проверить_отсутствие_конфликтных_стадий_проекции(корень: Path) -> None:
    конфликтные_пути = конфликтные_пути_проекции(корень)
    if конфликтные_пути:
        raise ОшибкаКонтракта(
            "Git-индекс содержит незакрытые конфликтные стадии проекции: "
            + ", ".join(sorted(конфликтные_пути))
        )


def прочитать_пути(корень: Path) -> list[str]:
    сырые_данные = выполнить_команду_контроля_версий(
        корень,
        "ls-files",
        "-z",
        "--cached",
        "--others",
        "--exclude-standard",
        двоичный=True,
    )
    assert isinstance(сырые_данные, bytes)
    пути: list[str] = []
    for сырой_путь in сырые_данные.split(b"\0"):
        if not сырой_путь:
            continue
        try:
            путь = сырой_путь.decode("utf-8")
        except UnicodeError as ошибка:
            raise ОшибкаКонтракта("Git-инвентарь содержит не-UTF-8 имя пути") from ошибка
        проверить_относительный_путь(путь, "исходный путь")
        if unicodedata.normalize("NFC", путь) != путь:
            raise ОшибкаКонтракта(f"Исходный путь не нормализован в NFC: {путь!r}")
        пути.append(путь)
    return sorted(set(пути), key=lambda путь: путь.encode("utf-8"))


def снимок_границы_репозитория(корень: Path) -> dict[str, str]:
    индекс = выполнить_команду_контроля_версий(
        корень,
        "ls-files",
        "-s",
        "-z",
        двоичный=True,
    )
    пути = выполнить_команду_контроля_версий(
        корень,
        "ls-files",
        "-z",
        "--cached",
        "--others",
        "--exclude-standard",
        двоичный=True,
    )
    assert isinstance(индекс, bytes)
    assert isinstance(пути, bytes)
    return {
        "вершина_репозитория": str(
            выполнить_команду_контроля_версий(корень, "rev-parse", "HEAD")
        ).strip(),
        "хэш_индекса": хэш_байтов(индекс),
        "хэш_набора_путей": хэш_байтов(пути),
    }


def путь_игнорируется_репозиторием(корень: Path, путь: str) -> bool:
    try:
        результат = subprocess.run(
            ["git", "-C", str(корень), "check-ignore", "-q", "--", путь],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            check=False,
            env=окружение_команды_контроля_версий(),
        )
    except OSError as ошибка:
        raise ОшибкаКонтракта(
            f"Не удалось вызвать Git для проверки игнорирования пути: {путь}"
        ) from ошибка
    if результат.returncode == 0:
        return True
    if результат.returncode == 1:
        return False
    raise ОшибкаКонтракта(
        "Не удалось определить Git-ignore для специального объекта: "
        + результат.stderr.decode("utf-8", errors="replace").strip()
    )


def получить_сведения_без_перехода(путь: Path, назначение: str) -> os.stat_result:
    try:
        return путь.lstat()
    except OSError as ошибка:
        raise ОшибкаКонтракта(
            f"Не удалось получить сведения об объекте {назначение}: {путь}"
        ) from ошибка


def проверить_неучтённые_специальные_объекты(
    корень: Path,
    политика: Mapping[str, Any],
    известные_пути: set[str],
) -> None:
    def отказ_обхода(ошибка: OSError) -> None:
        raise ОшибкаКонтракта(
            f"Не удалось полностью обследовать рабочее дерево: {ошибка}"
        ) from ошибка

    for текущий_каталог, каталоги, файлы in os.walk(
        корень,
        topdown=True,
        followlinks=False,
        onerror=отказ_обхода,
    ):
        текущий = Path(текущий_каталог)
        относительный_каталог = текущий.relative_to(корень).as_posix()
        if относительный_каталог == ".":
            относительный_каталог = ""
        допущенные_каталоги: list[str] = []
        for имя in каталоги:
            относительный = (
                f"{относительный_каталог}/{имя}"
                if относительный_каталог
                else имя
            )
            путь = текущий / имя
            сведения = получить_сведения_без_перехода(
                путь,
                "рабочего дерева",
            )
            if относительный in известные_пути:
                continue
            if относительный == ".git" or путь_под_префиксом(
                относительный,
                "Подузлы",
            ) or путь_под_префиксом(относительный, ПРОИЗВОДНОЕ_ПРОСТРАНСТВО):
                continue
            if stat.S_ISLNK(сведения.st_mode):
                if not путь_игнорируется_репозиторием(корень, относительный):
                    raise ОшибкаКонтракта(
                        f"Символическая ссылка не вошла в Git-инвентарь: {относительный}"
                    )
                continue
            if not stat.S_ISDIR(сведения.st_mode):
                if not путь_игнорируется_репозиторием(корень, относительный):
                    raise ОшибкаКонтракта(
                        f"Специальный файловый объект не вошёл в Git-инвентарь: {относительный}"
                    )
                continue
            if найти_исключение(f"{относительный}/служебный", политика) is None:
                допущенные_каталоги.append(имя)
        каталоги[:] = допущенные_каталоги

        for имя in файлы:
            относительный = (
                f"{относительный_каталог}/{имя}"
                if относительный_каталог
                else имя
            )
            if относительный in известные_пути or относительный == ".git":
                continue
            сведения = получить_сведения_без_перехода(
                текущий / имя,
                "рабочего дерева",
            )
            if stat.S_ISREG(сведения.st_mode):
                continue
            if not путь_игнорируется_репозиторием(корень, относительный):
                raise ОшибкаКонтракта(
                    f"Специальный файловый объект не вошёл в Git-инвентарь: {относительный}"
                )


def проверить_цепочку_без_ссылок(корень: Path, путь: str) -> os.stat_result:
    текущий = корень
    сведения: os.stat_result | None = None
    части = путь.split("/")
    for номер, часть in enumerate(части):
        текущий = текущий / часть
        try:
            сведения = текущий.lstat()
        except OSError as ошибка:
            raise ОшибкаКонтракта(
                f"Путь исчез или недоступен в рабочем дереве: {путь}"
            ) from ошибка
        if stat.S_ISLNK(сведения.st_mode):
            граница = "предок" if номер < len(части) - 1 else "объект"
            raise ОшибкаКонтракта(
                f"Символическая ссылка подменила {граница} исходного пути: {путь}"
            )
        if номер < len(части) - 1 and not stat.S_ISDIR(сведения.st_mode):
            raise ОшибкаКонтракта(f"Предок исходного пути не является каталогом: {путь}")
    assert сведения is not None
    return сведения


def определить_тип_и_режим(
    корень: Path,
    путь: str,
    индекс: Mapping[str, Mapping[str, str]],
) -> tuple[str, str, str | None]:
    индексная_запись = индекс.get(путь)
    if индексная_запись is not None:
        режим_индекса = индексная_запись["режим"]
        объект = индексная_запись["идентификатор_объекта_репозитория"]
        if режим_индекса == "160000":
            return "ссылка_на_вложенный_репозиторий", режим_индекса, объект
        if режим_индекса == "120000":
            return "символическая_ссылка", режим_индекса, объект
        if режим_индекса not in {"100644", "100755"}:
            raise ОшибкаКонтракта(
                f"Неподдержанный режим Git {режим_индекса} у {путь}"
            )
        сведения = проверить_цепочку_без_ссылок(корень, путь)
        if not stat.S_ISREG(сведения.st_mode):
            raise ОшибкаКонтракта(
                f"Отслеживаемый файл подменён специальным объектом: {путь}"
            )
        режим = "100755" if сведения.st_mode & 0o111 else "100644"
        return "обычный_файл", режим, объект

    сведения = проверить_цепочку_без_ссылок(корень, путь)
    if stat.S_ISREG(сведения.st_mode):
        режим = "100755" if сведения.st_mode & 0o111 else "100644"
        return "обычный_файл", режим, None
    raise ОшибкаКонтракта(f"Специальный файловый объект не поддерживается: {путь}")


def найти_исключение(путь: str, политика: Mapping[str, Any]) -> str | None:
    if путь_под_префиксом(путь, ПРОИЗВОДНОЕ_ПРОСТРАНСТВО):
        return "производное_пространство"
    if путь_под_префиксом(путь, "Подузлы"):
        return "пул_рабочих_деревьев"
    структурные = политика["структурные_исключения"]
    for точный_путь in структурные["пути"]:
        if путь_под_префиксом(путь, точный_путь):
            return f"структурный_путь:{точный_путь}"
    for компонент in путь.split("/")[:-1]:
        if компонент in структурные["имена_каталогов"]:
            return f"структурный_каталог:{компонент}"
        if any(
            компонент.endswith(окончание)
            for окончание in структурные["окончания_каталогов"]
        ):
            return f"структурный_кэш:{компонент}"
    return None


def безопасно_прочитать_файл_со_сведениями(
    корень: Path,
    путь: str,
) -> tuple[bytes, os.stat_result]:
    проверить_относительный_путь(путь, "безопасно читаемый путь")
    if not hasattr(os, "O_NOFOLLOW") or not hasattr(os, "O_DIRECTORY"):
        raise ОшибкаКонтракта(
            "Платформа не предоставляет O_NOFOLLOW и O_DIRECTORY для безопасного чтения"
        )
    открытые_каталоги: list[int] = []
    дескриптор_файла: int | None = None
    try:
        try:
            открытые_каталоги.append(
                os.open(
                    корень,
                    os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
                )
            )
            части_пути = путь.split("/")
            for компонент in части_пути[:-1]:
                открытые_каталоги.append(
                    os.open(
                        компонент,
                        os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
                        dir_fd=открытые_каталоги[-1],
                    )
                )
            дескриптор_файла = os.open(
                части_пути[-1],
                os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK,
                dir_fd=открытые_каталоги[-1],
            )
        except OSError as ошибка:
            raise ОшибкаКонтракта(
                f"Не удалось безопасно открыть исходный файл: {путь}"
            ) from ошибка
        assert дескриптор_файла is not None
        сведения_до = os.fstat(дескриптор_файла)
        if not stat.S_ISREG(сведения_до.st_mode):
            raise ОшибкаКонтракта(f"Исходный путь перестал быть обычным файлом: {путь}")
        части: list[bytes] = []
        while True:
            часть = os.read(дескриптор_файла, 1024 * 1024)
            if not часть:
                break
            части.append(часть)
        данные = b"".join(части)
        сведения_после = os.fstat(дескриптор_файла)
        if (
            сведения_до.st_ino != сведения_после.st_ino
            or сведения_до.st_size != сведения_после.st_size
            or сведения_до.st_mtime_ns != сведения_после.st_mtime_ns
            or len(данные) != сведения_после.st_size
        ):
            raise ОшибкаКонтракта(
                f"Исходный файл изменился во время безопасного чтения: {путь}"
            )
        return данные, сведения_после
    finally:
        if дескриптор_файла is not None:
            os.close(дескриптор_файла)
        for дескриптор_каталога in reversed(открытые_каталоги):
            os.close(дескриптор_каталога)


def безопасно_прочитать_обычный_файл(корень: Path, путь: str) -> bytes:
    данные, _ = безопасно_прочитать_файл_со_сведениями(корень, путь)
    return данные


def собрать_полный_инвентарь(
    корень: Path,
    политика: Mapping[str, Any],
) -> list[dict[str, Any]]:
    индекс = прочитать_индекс(корень)
    пути = прочитать_пути(корень)
    проверить_неучтённые_специальные_объекты(корень, политика, set(пути))
    результат: list[dict[str, Any]] = []
    найдена_зависимость = False
    for путь in пути:
        if путь_под_префиксом(путь, ПРОИЗВОДНОЕ_ПРОСТРАНСТВО):
            continue
        тип, режим, объект = определить_тип_и_режим(корень, путь, индекс)
        индексная_запись = индекс.get(путь)
        режим_индекса = None if индексная_запись is None else индексная_запись["режим"]
        состояние_репозитория = (
            "новый" if индексная_запись is None else "отслеживаемый"
        )

        if тип == "ссылка_на_вложенный_репозиторий":
            if путь != ПУТЬ_ЗАВИСИМОСТИ or объект != РЕВИЗИЯ_ЗАВИСИМОСТИ:
                raise ОшибкаКонтракта(
                    f"gitlink вне exact закреплённой зависимости запрещён: {путь}@{объект}"
                )
            найдена_зависимость = True
            результат.append(
                {
                    "исходный_путь": путь,
                    "тип": тип,
                    "режим": режим,
                    "режим_индекса": режим_индекса,
                    "состояние_репозитория": состояние_репозитория,
                    "идентификатор_объекта_репозитория": объект,
                    "состояние": "исключён",
                    "причина": "внешняя_зависимость_репозитория_только_метаданные",
                    "входит_в_исходный_снимок": True,
                    "размер_источника": None,
                    "хэш_источника": None,
                }
            )
            continue

        if тип == "символическая_ссылка":
            raise ОшибкаКонтракта(
                f"символическая ссылка требует отдельной политики: {путь}"
            )
        исключение = найти_исключение(путь, политика)
        if исключение is not None:
            результат.append(
                {
                    "исходный_путь": путь,
                    "тип": тип,
                    "режим": режим,
                    "режим_индекса": режим_индекса,
                    "состояние_репозитория": состояние_репозитория,
                    "идентификатор_объекта_репозитория": объект,
                    "состояние": "исключён",
                    "причина": исключение,
                    "входит_в_исходный_снимок": False,
                    "размер_источника": None,
                    "хэш_источника": None,
                }
            )
            continue
        данные = безопасно_прочитать_обычный_файл(корень, путь)
        результат.append(
            {
                "исходный_путь": путь,
                "тип": тип,
                "режим": режим,
                "режим_индекса": режим_индекса,
                "состояние_репозитория": состояние_репозитория,
                "идентификатор_объекта_репозитория": объект,
                "состояние": "включён",
                "причина": "каноническая_память",
                "входит_в_исходный_снимок": True,
                "размер_источника": len(данные),
                "хэш_источника": хэш_байтов(данные),
            }
        )
    if not найдена_зависимость:
        raise ОшибкаКонтракта(
            f"В Git-инвентаре отсутствует обязательный gitlink {ПУТЬ_ЗАВИСИМОСТИ}"
        )
    return результат


def расширения(форматы: Mapping[str, Any], имя: str) -> set[str]:
    return {значение.casefold() for значение in форматы[имя].get("расширения", [])}


def классифицировать_содержимое(
    корень: Path,
    путь: str,
    политика: Mapping[str, Any],
    данные: bytes | None = None,
) -> tuple[str, str, str]:
    if данные is None:
        данные = безопасно_прочитать_обычный_файл(корень, путь)
    try:
        данные.decode("utf-8")
        текстовый = b"\0" not in данные
    except UnicodeDecodeError:
        текстовый = False
    форматы = политика["форматы"]
    if not текстовый:
        return (
            "двоичный_или_нетекстовый",
            форматы["двоичные_и_нетекстовые"]["действие"],
            "явная_политика_непреобразуемых_байтов",
        )
    for окончание in форматы["машинные_шаблоны"]["окончания"]:
        if путь.endswith(окончание):
            return (
                "машинный_шаблон",
                форматы["машинные_шаблоны"]["действие"],
                f"машинный_шаблон:{окончание}",
            )
    запрос = форматы["разметка_с_дословным_блоком"]
    for шаблон in запрос["шаблоны"]:
        if fnmatch.fnmatchcase(путь, шаблон):
            return (
                "разметка_с_дословным_блоком",
                запрос["действие"],
                f"защищён_только_блок:{запрос['заголовок_начала']}",
            )
    for шаблон in форматы["дословные_источники"]["шаблоны"]:
        if fnmatch.fnmatchcase(путь, шаблон):
            return (
                "дословный_источник",
                форматы["дословные_источники"]["действие"],
                f"дословный_шаблон:{шаблон}",
            )
    суффикс = PurePosixPath(путь).suffix.casefold()
    if суффикс in расширения(форматы, "разметка"):
        return (
            "разметка",
            форматы["разметка"]["действие"],
            "структурная_политика_разметки_ссылок_якорей_и_свежести",
        )
    if суффикс in расширения(форматы, "код"):
        return "код", форматы["код"]["действие"], "точные_контракты_кода"
    if суффикс in расширения(форматы, "машинные_данные"):
        return (
            "машинные_данные",
            форматы["машинные_данные"]["действие"],
            "точный_машинный_формат",
        )
    прочие = форматы["прочие_точные_форматы"]
    if путь in прочие["точные_пути"] or суффикс in расширения(
        форматы,
        "прочие_точные_форматы",
    ):
        return (
            "прочий_точный_формат",
            прочие["действие"],
            "явно_зарегистрированный_точный_формат",
        )
    raise ОшибкаКонтракта(f"Неизвестный формат закрывает план: {путь}")


def основа_и_расширение(
    компонент: str,
    последний: bool,
    сохраняемые_расширения: Sequence[str],
) -> tuple[str, str]:
    if not последний:
        return компонент, ""
    for суффикс in sorted(сохраняемые_расширения, key=len, reverse=True):
        if компонент.casefold().endswith(суффикс.casefold()) and len(компонент) > len(суффикс):
            return компонент[: -len(суффикс)], компонент[-len(суффикс) :]
    return компонент, ""


def проверить_переносимость_компонента(
    компонент: str,
    ограничения: Mapping[str, Any],
    путь: str,
) -> None:
    if not компонент or компонент in {".", ".."} or "/" in компонент or "\0" in компонент:
        raise ОшибкаКонтракта(
            f"Непереносимый целевой компонент у {путь}: {компонент!r}"
        )
    if unicodedata.normalize("NFC", компонент) != компонент:
        raise ОшибкаКонтракта(
            f"NFC-непереносимый целевой компонент у {путь}: {компонент!r}"
        )
    if any("CYRILLIC" in unicodedata.name(знак, "") for знак in компонент):
        raise ОшибкаКонтракта(
            f"LinguisticKit оставил кириллицу в целевом компоненте у {путь}: {компонент!r}"
        )
    if компонент.endswith((" ", ".")):
        raise ОшибкаКонтракта(
            f"Непереносимый целевой компонент у {путь}: конечная точка или пробел"
        )
    if any(ord(знак) < 32 or знак in '<>:"\\|?*' for знак in компонент):
        raise ОшибкаКонтракта(
            f"Непереносимый целевой компонент у {путь}: запрещённый знак"
        )
    основа = компонент.split(".", 1)[0].casefold()
    зарезервированные = {
        имя.casefold()
        for имя in ограничения["зарезервированные_системные_имена"]
    }
    номера = {str(номер) for номер in range(1, 10)}
    if (
        основа in зарезервированные
        or (основа.startswith("com") and основа[3:] in номера)
        or (основа.startswith("lpt") and основа[3:] in номера)
    ):
        raise ОшибкаКонтракта(
            f"непереносимое зарезервированное имя у {путь}: {компонент}"
        )
    if len(компонент.encode("utf-8")) > ограничения["максимум_байтов_компонента"]:
        raise ОшибкаКонтракта(
            f"Слишком длинный целевой компонент у {путь}: {компонент}"
        )
    единицы_кодировки = len(компонент.encode("utf-16-le")) // 2
    if единицы_кодировки > ограничения["максимум_кодовых_единиц_UTF_16_компонента"]:
        raise ОшибкаКонтракта(
            f"Слишком длинный целевой компонент в UTF-16 у {путь}: {компонент}"
        )


def преобразовать_пути(
    исходные_пути: Sequence[str],
    корень_файлов: str,
    ограничения: Mapping[str, Any],
    сохраняемые_расширения: Sequence[str],
    преобразователь: Callable[[Sequence[str]], Sequence[str]],
) -> dict[str, tuple[str, list[dict[str, Any]]]]:
    разбор: dict[str, list[tuple[str, str]]] = {}
    основы: set[str] = set()
    for путь in исходные_пути:
        компоненты = путь.split("/")
        части: list[tuple[str, str]] = []
        for номер, компонент in enumerate(компоненты):
            основа, суффикс = основа_и_расширение(
                компонент,
                номер == len(компоненты) - 1,
                сохраняемые_расширения,
            )
            основы.add(основа)
            части.append((основа, суффикс))
        разбор[путь] = части
    задания = sorted(основы, key=lambda строка: строка.encode("utf-8"))
    try:
        ответы = list(преобразователь(задания))
    except ОшибкаКонтракта:
        raise
    except Exception as ошибка:
        raise ОшибкаКонтракта(
            f"Преобразователь LinguisticKit завершился ошибкой: {ошибка}"
        ) from ошибка
    if len(ответы) != len(задания) or not all(
        isinstance(ответ, str) for ответ in ответы
    ):
        raise ОшибкаКонтракта(
            "Преобразователь LinguisticKit нарушил контракт массива строк"
        )
    соответствия = dict(zip(задания, ответы, strict=True))

    результат: dict[str, tuple[str, list[dict[str, Any]]]] = {}
    for путь in исходные_пути:
        целевые_компоненты: list[str] = []
        отображение: list[dict[str, Any]] = []
        исходные_компоненты = путь.split("/")
        for исходный_компонент, (основа, суффикс) in zip(
            исходные_компоненты,
            разбор[путь],
            strict=True,
        ):
            преобразованная_основа = соответствия[основа]
            целевой_компонент = преобразованная_основа + суффикс
            проверить_переносимость_компонента(
                целевой_компонент,
                ограничения,
                путь,
            )
            целевые_компоненты.append(целевой_компонент)
            отображение.append(
                {
                    "исходный": исходный_компонент,
                    "целевая_основа": преобразованная_основа,
                    "сохранённое_расширение": суффикс,
                    "целевой": целевой_компонент,
                    "изменён": целевой_компонент != исходный_компонент,
                }
            )
        целевой_путь = "/".join([корень_файлов, *целевые_компоненты])
        if len(целевой_путь.encode("utf-8")) > ограничения["максимум_байтов_пути"]:
            raise ОшибкаКонтракта(f"Слишком длинный целевой путь: {целевой_путь}")
        результат[путь] = целевой_путь, отображение
    return результат


def проверить_коллизии(отображение: Mapping[str, str]) -> None:
    def проверить_ключи(название: str, ключ: Callable[[str], str]) -> None:
        увиденные: dict[str, str] = {}
        for исходный, целевой in sorted(
            отображение.items(),
            key=lambda пара: пара[0].encode("utf-8"),
        ):
            значение = ключ(целевой)
            прежний = увиденные.get(значение)
            if прежний is not None and прежний != исходный:
                raise ОшибкаКонтракта(
                    f"{название}-коллизия целевых путей: "
                    f"{прежний} и {исходный} → {целевой}"
                )
            увиденные[значение] = исходный

    проверить_ключи("exact", lambda путь: путь)
    проверить_ключи("NFC", lambda путь: unicodedata.normalize("NFC", путь))
    проверить_ключи(
        "casefold",
        lambda путь: unicodedata.normalize("NFC", путь).casefold(),
    )
    нормализованные = {
        исходный: tuple(
            unicodedata.normalize("NFC", компонент).casefold()
            for компонент in целевой.split("/")
        )
        for исходный, целевой in отображение.items()
    }
    элементы = sorted(
        нормализованные.items(),
        key=lambda пара: пара[0].encode("utf-8"),
    )
    for номер, (исходный, компоненты) in enumerate(элементы):
        for другой_исходный, другие_компоненты in элементы[номер + 1 :]:
            префикс = (
                len(компоненты) < len(другие_компоненты)
                and другие_компоненты[: len(компоненты)] == компоненты
            ) or (
                len(другие_компоненты) < len(компоненты)
                and компоненты[: len(другие_компоненты)] == другие_компоненты
            )
            if префикс:
                raise ОшибкаКонтракта(
                    "Коллизия файл–каталог целевых путей: "
                    f"{исходный} и {другой_исходный}"
                )


ПОЛЯ_НАБЛЮДЕНИЯ_РЕПОЗИТОРИЯ = {
    "режим_индекса",
    "состояние_репозитория",
    "идентификатор_объекта_репозитория",
}


def устойчивая_проекция_записи(запись: Mapping[str, Any]) -> dict[str, Any]:
    return {
        ключ: значение
        for ключ, значение in запись.items()
        if ключ not in ПОЛЯ_НАБЛЮДЕНИЯ_РЕПОЗИТОРИЯ
    }


def вычислить_хэш_плана(план: Mapping[str, Any]) -> str:
    смысловой_план = dict(план)
    смысловой_план.pop("хэш_плана", None)
    смысловой_план.pop("полный_инвентарь", None)
    смысловой_план["записи"] = [
        устойчивая_проекция_записи(запись)
        for запись in план["записи"]
    ]
    return хэш_значения(смысловой_план)


def построить_план(
    корень_репозитория: Path | str,
    политика: Mapping[str, Any],
    преобразователь: Callable[[Sequence[str]], Sequence[str]],
    *,
    разрешить_управляемую_цель: bool = False,
    разрешить_конфликтную_цель: bool = False,
    разрешить_квитанцию_установки: bool = False,
) -> dict[str, Any]:
    корень = Path(корень_репозитория).resolve()
    if str(
        выполнить_команду_контроля_версий(корень, "rev-parse", "--show-toplevel")
    ).strip() != str(корень):
        raise ОшибкаКонтракта("Корень репозитория не совпадает с Git toplevel")
    проверенная_политика = проверить_политику(политика)
    if (
        not разрешить_квитанцию_установки
        and прочитать_квитанцию_установки(корень) is not None
    ):
        raise ОшибкаКонтракта(
            "Незавершённая внешняя квитанция закрывает план и валидацию"
        )
    граница_до = снимок_границы_репозитория(корень)
    наблюдаемый_инвентарь = собрать_полный_инвентарь(корень, проверенная_политика)
    try:
        (корень / ПРОИЗВОДНОЕ_ПРОСТРАНСТВО).lstat()
        производное_пространство_существует = True
    except FileNotFoundError:
        производное_пространство_существует = False
    except OSError as ошибка:
        raise ОшибкаКонтракта("Не удалось обследовать производное пространство") from ошибка
    if (
        производное_пространство_существует
        and not разрешить_конфликтную_цель
    ):
        проверить_производное_пространство(
            корень,
            проверенная_политика,
            разрешить_служебный_каталог=разрешить_управляемую_цель,
        )
    полный_инвентарь = наблюдаемый_инвентарь
    включённые = [
        запись for запись in полный_инвентарь if запись["состояние"] == "включён"
    ]
    исходные_пути = [запись["исходный_путь"] for запись in включённые]
    преобразованные = преобразовать_пути(
        исходные_пути,
        КОРЕНЬ_ФАЙЛОВ,
        проверенная_политика["ограничения_пути"],
        проверенная_политика["сохраняемые_технические_расширения"],
        преобразователь,
    )
    проверить_коллизии(
        {путь: преобразованные[путь][0] for путь in исходные_пути}
    )
    записи: list[dict[str, Any]] = []
    for инвентарная_запись in включённые:
        путь = инвентарная_запись["исходный_путь"]
        целевой_путь, компоненты = преобразованные[путь]
        данные_для_классификации = безопасно_прочитать_обычный_файл(
            корень,
            путь,
        )
        if хэш_байтов(данные_для_классификации) != инвентарная_запись["хэш_источника"]:
            raise ОшибкаКонтракта(
                f"Исходный файл изменился между инвентаризацией и классификацией: {путь}"
            )
        класс, действие, причина = классифицировать_содержимое(
            корень,
            путь,
            проверенная_политика,
            данные_для_классификации,
        )
        записи.append(
            {
                "исходный_путь": путь,
                "целевой_путь": целевой_путь,
                "компоненты_пути": компоненты,
                "тип": инвентарная_запись["тип"],
                "режим": инвентарная_запись["режим"],
                "режим_индекса": инвентарная_запись["режим_индекса"],
                "состояние_репозитория": инвентарная_запись[
                    "состояние_репозитория"
                ],
                "идентификатор_объекта_репозитория": инвентарная_запись[
                    "идентификатор_объекта_репозитория"
                ],
                "размер_источника": инвентарная_запись["размер_источника"],
                "хэш_источника": инвентарная_запись["хэш_источника"],
                "класс_содержимого": класс,
                "действие_содержимого": действие,
                "причина_действия": причина,
                "хэш_цели": None,
            }
        )
    снимок_инвентаря = [
        устойчивая_проекция_записи(запись)
        for запись in полный_инвентарь
        if запись["входит_в_исходный_снимок"]
    ]
    хэш_политики = хэш_значения(проверенная_политика)
    исходный_снимок = {
        "хэш_инвентаря": хэш_значения(снимок_инвентаря),
        "хэш_политики": хэш_политики,
    }
    итоговые_пути = sorted(
        (запись["целевой_путь"] for запись in записи),
        key=lambda путь: путь.encode("utf-8"),
    )
    повторный_инвентарь = собрать_полный_инвентарь(корень, проверенная_политика)
    граница_после = снимок_границы_репозитория(корень)
    if повторный_инвентарь != наблюдаемый_инвентарь:
        raise ОшибкаКонтракта(
            "Исходный снимок изменился во время построения плана; требуется повторный запуск"
        )
    if граница_после != граница_до:
        raise ОшибкаКонтракта(
            "Целевое поколение изменилось во время построения плана"
        )
    план: dict[str, Any] = {
        "схема": СХЕМА_ПЛАНА,
        "хэш_плана": None,
        "исходный_снимок": исходный_снимок,
        "хэш_политики": хэш_политики,
        "исходная_область": ".",
        "производное_пространство": ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
        "целевая_область": ЦЕЛЕВАЯ_ОБЛАСТЬ,
        "корень_файлов": КОРЕНЬ_ФАЙЛОВ,
        "путь_манифеста": ПУТЬ_МАНИФЕСТА,
        "исключённые_префиксы": проверенная_политика["исключённые_префиксы"],
        "преобразование": dict(проверенная_политика["преобразование"]),
        "форматная_политика": проверенная_политика["форматы"],
        "пустые_каталоги": проверенная_политика["пустые_каталоги"],
        "полный_инвентарь": полный_инвентарь,
        "записи": записи,
        "итоговые_целевые_пути": итоговые_пути,
        "состояние": "готов_без_записи",
    }
    план["хэш_плана"] = вычислить_хэш_плана(план)
    return план


def выполнить_преобразование_строк(
    значения: Sequence[str],
    преобразователь: Callable[[Sequence[str]], Sequence[str]],
) -> dict[str, str]:
    задания = sorted(set(значения), key=lambda строка: строка.encode("utf-8"))
    if not задания:
        return {}
    try:
        ответы = list(преобразователь(задания))
    except ОшибкаКонтракта:
        raise
    except Exception as ошибка:
        raise ОшибкаКонтракта(
            f"Преобразователь LinguisticKit завершился ошибкой: {ошибка}"
        ) from ошибка
    if len(ответы) != len(задания) or not all(
        isinstance(ответ, str) for ответ in ответы
    ):
        raise ОшибкаКонтракта(
            "Преобразователь LinguisticKit нарушил контракт массива строк"
        )
    return dict(zip(задания, ответы, strict=True))


def нормализовать_якорь(текст: str) -> str:
    текст = re.sub(
        r"!?(?:\[([^]\n]*)\])(?:\([^\n)]*\)|\[[^\n]]*\])",
        r"\1",
        текст,
    )
    текст = текст.replace("`", "").strip().casefold()
    текст = "".join(
        знак for знак in текст if знак.isalnum() or знак in " _-"
    )
    return re.sub(r"[ \t]+", "-", текст)


def последовательность_якорей_разметки(текст: str) -> list[str]:
    анализатор = модуль_структурной_разметки()
    маска = анализатор.markdown_hidden_mask(текст)
    якоря: list[str] = []
    использованные_якоря: set[str] = set()
    for начало, _конец, строка in анализатор.line_ranges(текст):
        содержание = строка.rstrip("\r\n")
        видимое = "".join(
            " " if маска[позиция] else текст[позиция]
            for позиция in range(начало, начало + len(содержание))
        )
        видимое_совпадение = ЗАГОЛОВОК_РАЗМЕТКИ.match(видимое)
        if видимое_совпадение is None:
            continue
        исходное_совпадение = ЗАГОЛОВОК_РАЗМЕТКИ.match(содержание)
        if исходное_совпадение is None:
            raise ОшибкаКонтракта("Видимый Markdown-заголовок не разобран")
        основа = нормализовать_якорь(
            исходное_совпадение.group("текст")
        )
        якорь = основа
        номер = 1
        while якорь in использованные_якоря:
            якорь = f"{основа}-{номер}"
            номер += 1
        использованные_якоря.add(якорь)
        якоря.append(якорь)
    return якоря


def якоря_разметки(текст: str) -> set[str]:
    return set(последовательность_якорей_разметки(текст))


def построить_карты_целей(
    план: Mapping[str, Any],
) -> tuple[dict[str, str], dict[str, str]]:
    файлы: dict[str, str] = {}
    каталоги: dict[str, str] = {".": КОРЕНЬ_ФАЙЛОВ}
    for запись in план["записи"]:
        исходный = запись["исходный_путь"]
        целевой = запись["целевой_путь"]
        файлы[исходный] = целевой
        исходные_части = PurePosixPath(исходный).parts
        целевые_части = PurePosixPath(целевой).parts
        корневые_части = PurePosixPath(КОРЕНЬ_ФАЙЛОВ).parts
        остаток = целевые_части[len(корневые_части) :]
        if len(остаток) != len(исходные_части):
            raise ОшибкаКонтракта(
                f"План содержит несогласованные компоненты пути: {исходный}"
            )
        for глубина in range(1, len(исходные_части)):
            исходный_каталог = "/".join(исходные_части[:глубина])
            целевой_каталог = "/".join(
                [*корневые_части, *остаток[:глубина]]
            )
            прежний = каталоги.setdefault(исходный_каталог, целевой_каталог)
            if прежний != целевой_каталог:
                raise ОшибкаКонтракта(
                    f"План неоднозначно отображает каталог: {исходный_каталог}"
                )
    return файлы, каталоги


def разобрать_фрагмент_ссылки(
    суффикс: str,
    контекст: str,
) -> tuple[str, str | None]:
    if "#" not in суффикс:
        return суффикс, None
    до_фрагмента, сырой_фрагмент = суффикс.split("#", 1)
    анализатор = модуль_структурной_разметки()
    try:
        декодированный = анализатор.strict_percent_decode(
            анализатор.markdown_unescape(сырой_фрагмент),
            контекст,
        )
    except Exception as ошибка:
        raise ОшибкаКонтракта(
            f"Некорректный фрагмент локальной Markdown-ссылки в {контекст}: {ошибка}"
        ) from ошибка
    if not декодированный:
        raise ОшибкаКонтракта(
            f"Пустой фрагмент локальной Markdown-ссылки в {контекст}"
        )
    return до_фрагмента, декодированный


def создать_защищённый_текст(
    текст: str,
    маска: bytearray,
    номер_документа: int,
) -> tuple[str, dict[str, str]]:
    замены: dict[str, str] = {}
    части: list[str] = []
    позиция = 0
    номер = 0
    while позиция < len(текст):
        if not маска[позиция]:
            начало = позиция
            while позиция < len(текст) and not маска[позиция]:
                позиция += 1
            части.append(текст[начало:позиция])
            continue
        начало = позиция
        while позиция < len(текст) and маска[позиция]:
            позиция += 1
        токен = f"FUMZASHCHITA{номер_документа:08d}{номер:08d}X"
        if токен in текст:
            raise ОшибкаКонтракта("Защитный токен уже присутствует в Markdown")
        замены[токен] = текст[начало:позиция]
        части.append(токен)
        номер += 1
    return "".join(части), замены


def восстановить_защищённый_текст(
    текст: str,
    замены: Mapping[str, str],
    путь: str,
) -> str:
    результат = текст
    for токен, значение in замены.items():
        if результат.count(токен) != 1:
            raise ОшибкаКонтракта(
                f"LinguisticKit изменил защитный токен Markdown: {путь}"
            )
        результат = результат.replace(токен, значение)
    if "FUMZASHCHITA" in результат:
        raise ОшибкаКонтракта(
            f"После восстановления Markdown остался неизвестный защитный токен: {путь}"
        )
    return результат


def сформировать_выходы(
    корень_репозитория: Path | str,
    план: Mapping[str, Any],
    преобразователь: Callable[[Sequence[str]], Sequence[str]],
) -> dict[str, bytes]:
    корень = Path(корень_репозитория).resolve()
    if план.get("схема") != СХЕМА_ПЛАНА:
        raise ОшибкаКонтракта("Выходы можно сформировать только из плана версии 2")
    if план.get("хэш_плана") != вычислить_хэш_плана(план):
        raise ОшибкаКонтракта("План повреждён: собственный хэш не совпадает")
    файлы_целей, каталоги_целей = построить_карты_целей(план)
    записи_по_источникам = {
        запись["исходный_путь"]: запись for запись in план["записи"]
    }
    исключённые_пути = {
        запись["исходный_путь"]
        for запись in план["полный_инвентарь"]
        if запись["состояние"] == "исключён"
    }
    исключённые_пути.update(ТОЧНЫЕ_СТРУКТУРНЫЕ_ИСКЛЮЧЁННЫЕ_ПУТИ)
    ожидаемые_производные_файлы = {
        *план["итоговые_целевые_пути"],
        ПУТЬ_МАНИФЕСТА,
    }
    ожидаемые_производные_каталоги: set[str] = set()
    for ожидаемый_файл in ожидаемые_производные_файлы:
        предок = PurePosixPath(ожидаемый_файл).parent
        while путь_под_префиксом(
            предок.as_posix(),
            ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
        ):
            ожидаемые_производные_каталоги.add(предок.as_posix())
            if предок.as_posix() == ПРОИЗВОДНОЕ_ПРОСТРАНСТВО:
                break
            предок = предок.parent
    анализатор = модуль_структурной_разметки()
    подготовки: list[dict[str, Any]] = []
    точные_выходы: dict[str, bytes] = {}
    задания: list[str] = []
    проверки_якорей: list[dict[str, str]] = []
    исходные_якоря: dict[str, list[str]] = {}

    for номер_документа, запись in enumerate(план["записи"]):
        исходный_путь = запись["исходный_путь"]
        исходные_байты = безопасно_прочитать_обычный_файл(корень, исходный_путь)
        if хэш_байтов(исходные_байты) != запись["хэш_источника"]:
            raise ОшибкаКонтракта(
                f"Исходный файл изменился после плана: {исходный_путь}"
            )
        if запись["действие_содержимого"] == "сохранить_байты":
            точные_выходы[запись["целевой_путь"]] = исходные_байты
            continue
        try:
            исходный_текст = исходные_байты.decode("utf-8")
        except UnicodeDecodeError as ошибка:
            raise ОшибкаКонтракта(
                f"Структурная разметка не является UTF-8: {исходный_путь}"
            ) from ошибка
        содержание, время_свежести = разделить_свежесть(
            исходный_текст,
            исходный_путь,
        )
        if "FUMYAKOR" in содержание or "FUMZASHCHITA" in содержание:
            raise ОшибкаКонтракта(
                f"Markdown содержит зарезервированный маркер проекции: {исходный_путь}"
            )
        исходная_маска = анализатор.markdown_hidden_mask(содержание)
        защищённые_разделы: tuple[tuple[int, int], ...] = ()
        if запись["действие_содержимого"] == "преобразовать_разметку_с_дословным_блоком":
            try:
                защищённые_разделы = анализатор.request_text_spans(
                    содержание,
                    исходная_маска,
                    PurePosixPath(исходный_путь),
                )
            except Exception as ошибка:
                raise ОшибкаКонтракта(
                    f"Не удалось однозначно защитить ## Текст запроса в {исходный_путь}: {ошибка}"
                ) from ошибка
        замены_ссылок: list[tuple[int, int, str]] = []
        for номер_ссылки, токен in enumerate(
            анализатор.markdown_link_tokens(содержание, исходная_маска)
        ):
            if анализатор.position_in_spans(
                токен.destination_start,
                защищённые_разделы,
            ):
                continue
            try:
                назначение = анализатор.resolve_destination(
                    токен,
                    корень / PurePosixPath(исходный_путь),
                    корень,
                    PurePosixPath(исходный_путь),
                )
            except Exception as ошибка:
                raise ОшибкаКонтракта(
                    f"Некорректная Markdown-ссылка {исходный_путь}:{токен.line}: {ошибка}"
                ) from ошибка
            if not назначение.is_local:
                замены_ссылок.append(
                    (
                        токен.destination_start,
                        токен.destination_end,
                        токен.raw_destination,
                    )
                )
                continue
            assert назначение.target is not None
            цель_источника = назначение.target.relative_to(корень).as_posix()
            цель_в_новом_поколении = (
                цель_источника in ожидаемые_производные_файлы
                or цель_источника in ожидаемые_производные_каталоги
            )
            if (
                путь_под_префиксом(
                    цель_источника,
                    ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
                )
                and not цель_в_новом_поколении
            ):
                raise ОшибкаКонтракта(
                    "Локальная Markdown-ссылка ведёт вне включённого поколения: "
                    f"{исходный_путь}:{токен.line} → {цель_источника}"
                )
            if not цель_в_новом_поколении:
                try:
                    анализатор.ensure_outgoing_target(
                        назначение,
                        токен,
                        PurePosixPath(исходный_путь),
                        корень,
                    )
                except Exception as ошибка:
                    raise ОшибкаКонтракта(
                        f"Неразрешимая локальная Markdown-ссылка {исходный_путь}:{токен.line}: {ошибка}"
                    ) from ошибка
            if цель_в_новом_поколении:
                цель_после = цель_источника
            elif назначение.target.is_dir():
                цель_после = каталоги_целей.get(
                    цель_источника if цель_источника else "."
                )
            else:
                цель_после = файлы_целей.get(цель_источника)
            if цель_после is None:
                if not any(
                    путь_под_префиксом(цель_источника, исключённый)
                    for исключённый in исключённые_пути
                ):
                    raise ОшибкаКонтракта(
                        "Локальная Markdown-ссылка ведёт вне включённого поколения: "
                        f"{исходный_путь}:{токен.line} → {цель_источника}"
                    )
                цель_после = цель_источника
            запрос, фрагмент = разобрать_фрагмент_ссылки(
                назначение.suffix,
                f"{исходный_путь}:{токен.line}",
            )
            if назначение.decoded_path:
                относительный = os.path.relpath(
                    корень / PurePosixPath(цель_после),
                    (корень / PurePosixPath(запись["целевой_путь"])).parent,
                ).replace(os.sep, "/")
                if назначение.decoded_path.endswith("/") and not относительный.endswith("/"):
                    относительный += "/"
                путь_назначения = анализатор.encode_destination_path(
                    относительный,
                    angle=токен.angle_destination,
                )
            else:
                путь_назначения = ""
            суффикс = запрос
            if фрагмент is not None:
                if цель_источника not in записи_по_источникам:
                    raise ОшибкаКонтракта(
                        f"Якорь ведёт в исключённый из поколения путь: {цель_источника}"
                    )
                целевая_запись = записи_по_источникам[цель_источника]
                преобразуемая_разметка = целевая_запись["класс_содержимого"] in {
                    "разметка",
                    "разметка_с_дословным_блоком",
                }
                точная_разметка = (
                    PurePosixPath(цель_источника).suffix.casefold() == ".md"
                    and целевая_запись["действие_содержимого"]
                    == "сохранить_байты"
                )
                if not преобразуемая_разметка and not точная_разметка:
                    raise ОшибкаКонтракта(
                        f"Якорь ведёт не в Markdown: {цель_источника}"
                    )
                if цель_источника not in исходные_якоря:
                    целевой_текст = безопасно_прочитать_обычный_файл(
                        корень,
                        цель_источника,
                    ).decode("utf-8")
                    целевое_содержание, _ = разделить_свежесть(
                        целевой_текст,
                        цель_источника,
                    )
                    исходные_якоря[цель_источника] = (
                        последовательность_якорей_разметки(целевое_содержание)
                    )
                if фрагмент.casefold() not in исходные_якоря[цель_источника]:
                    raise ОшибкаКонтракта(
                        "Локальная Markdown-ссылка содержит отсутствующий якорь: "
                        f"{исходный_путь}:{токен.line} → {цель_источника}#{фрагмент}"
                    )
                маркер = f"FUMYAKOR{номер_документа:08d}{номер_ссылки:08d}X"
                суффикс += "#" + маркер
                проверки_якорей.append(
                    {
                        "маркер": маркер,
                        "исходный_якорь": фрагмент,
                        "цель_источника": цель_источника,
                        "целевой_путь": цель_после,
                        "исходный_путь": исходный_путь,
                    }
                )
            замены_ссылок.append(
                (
                    токен.destination_start,
                    токен.destination_end,
                    путь_назначения + суффикс,
                )
            )
        переписанное = анализатор.apply_text_replacements(
            содержание,
            замены_ссылок,
        )
        маска = анализатор.markdown_hidden_mask(переписанное)
        if запись["действие_содержимого"] == "преобразовать_разметку_с_дословным_блоком":
            try:
                for начало, конец in анализатор.request_text_spans(
                    переписанное,
                    маска,
                    PurePosixPath(исходный_путь),
                ):
                    отметить_диапазон(маска, начало, конец)
            except Exception as ошибка:
                raise ОшибкаКонтракта(
                    f"Не удалось повторно защитить ## Текст запроса в {исходный_путь}: {ошибка}"
                ) from ошибка
        for токен in анализатор.markdown_link_tokens(переписанное, маска):
            отметить_диапазон(
                маска,
                токен.destination_start,
                токен.destination_end,
            )
        for выражение in (ГОЛЫЙ_ВНЕШНИЙ_АДРЕС, ВСТРОЕННАЯ_ГИПЕРТЕКСТОВАЯ_РАЗМЕТКА):
            for совпадение in выражение.finditer(переписанное):
                if not any(маска[совпадение.start() : совпадение.end()]):
                    отметить_диапазон(
                        маска,
                        совпадение.start(),
                        совпадение.end(),
                    )
        защищённый, защищённые_замены = создать_защищённый_текст(
            переписанное,
            маска,
            номер_документа,
        )
        задания.append(защищённый)
        подготовки.append(
            {
                "исходный_путь": исходный_путь,
                "целевой_путь": запись["целевой_путь"],
                "защищённый": защищённый,
                "замены": защищённые_замены,
                "время_свежести": время_свежести,
            }
        )

    соответствия = выполнить_преобразование_строк(
        задания,
        преобразователь,
    )
    выходы = dict(точные_выходы)
    структурные_результаты: dict[str, str] = {}
    for подготовка in подготовки:
        результат = восстановить_защищённый_текст(
            соответствия[подготовка["защищённый"]],
            подготовка["замены"],
            подготовка["исходный_путь"],
        )
        структурные_результаты[подготовка["целевой_путь"]] = результат

    карты_якорей: dict[str, dict[str, str]] = {}
    маркеры_якорей: dict[str, str] = {}
    for проверка in проверки_якорей:
        цель_источника = проверка["цель_источника"]
        целевой_путь = проверка["целевой_путь"]
        if цель_источника not in карты_якорей:
            целевой_текст = структурные_результаты.get(целевой_путь)
            if целевой_текст is None:
                точные_байты = точные_выходы.get(целевой_путь)
                if точные_байты is None:
                    raise ОшибкаКонтракта(
                        f"Преобразованный якорь ведёт вне поколения: {целевой_путь}"
                    )
                try:
                    целевой_текст = точные_байты.decode("utf-8")
                except UnicodeDecodeError as ошибка:
                    raise ОшибкаКонтракта(
                        f"Якорь ведёт в нетекстовый точный выход: {целевой_путь}"
                    ) from ошибка
            исходная_последовательность = исходные_якоря[цель_источника]
            целевая_последовательность = последовательность_якорей_разметки(
                целевой_текст
            )
            if len(исходная_последовательность) != len(целевая_последовательность):
                raise ОшибкаКонтракта(
                    f"Преобразование изменило число Markdown-заголовков: {цель_источника}"
                )
            карты_якорей[цель_источника] = dict(
                zip(
                    исходная_последовательность,
                    целевая_последовательность,
                    strict=True,
                )
            )
        ожидаемый = карты_якорей[цель_источника].get(
            проверка["исходный_якорь"].casefold()
        )
        if ожидаемый is None:
            raise ОшибкаКонтракта(
                "Преобразованный якорь не разрешается в поколении: "
                f"{проверка['исходный_путь']} → {целевой_путь}#{ожидаемый}"
            )
        маркеры_якорей[проверка["маркер"]] = анализатор.encode_destination_path(
            ожидаемый,
            angle=False,
        )

    for подготовка in подготовки:
        результат = структурные_результаты[подготовка["целевой_путь"]]
        for маркер, якорь in маркеры_якорей.items():
            if маркер in результат:
                результат = результат.replace(маркер, якорь)
        if "FUMYAKOR" in результат:
            raise ОшибкаКонтракта(
                f"После преобразования остался неизвестный маркер якоря: {подготовка['исходный_путь']}"
            )
        результат = присоединить_свежесть(
            подготовка["исходный_путь"],
            результат,
            подготовка["время_свежести"],
        )
        выходы[подготовка["целевой_путь"]] = результат.encode("utf-8")

    ожидаемые = set(план["итоговые_целевые_пути"])
    if set(выходы) != ожидаемые:
        raise ОшибкаКонтракта(
            "Генератор сформировал неполный набор выходов; "
            f"отсутствуют={sorted(ожидаемые - set(выходы))}, "
            f"лишние={sorted(set(выходы) - ожидаемые)}"
        )
    return выходы



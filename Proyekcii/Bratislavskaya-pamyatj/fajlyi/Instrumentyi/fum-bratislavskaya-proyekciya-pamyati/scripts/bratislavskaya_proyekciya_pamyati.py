def проверить_хэш(значение: Any, поле: str) -> str:
    if not isinstance(значение, str) or re.fullmatch(
        r"sha256:[0-9a-f]{64}",
        значение,
    ) is None:
        raise ОшибкаКонтракта(f"{поле}: требуется полный SHA-256")
    return значение


def копия_машинного_значения(значение: Any) -> Any:
    return json.loads(
        json.dumps(значение, ensure_ascii=False, allow_nan=False),
        parse_constant=отклонить_нестандартное_число,
    )


def сформировать_манифест(
    план: Mapping[str, Any],
    выходы: Mapping[str, bytes],
) -> dict[str, Any]:
    """Формирует испытательный манифест из байтов будущего генератора."""

    if план.get("схема") != СХЕМА_ПЛАНА:
        raise ОшибкаКонтракта("Манифест можно сформировать только из плана версии 2")
    if план.get("хэш_плана") != вычислить_хэш_плана(план):
        raise ОшибкаКонтракта("План повреждён: собственный хэш не совпадает")
    ожидаемые = set(план["итоговые_целевые_пути"])
    фактические = set(выходы)
    if ожидаемые != фактические:
        raise ОшибкаКонтракта(
            "Неполный набор выходов манифеста; "
            f"отсутствуют={sorted(ожидаемые - фактические)}, "
            f"лишние={sorted(фактические - ожидаемые)}"
        )
    записи: list[dict[str, Any]] = []
    for запись in план["записи"]:
        данные = выходы[запись["целевой_путь"]]
        if not isinstance(данные, bytes):
            raise ОшибкаКонтракта(
                "Выходы манифеста обязаны передаваться точными байтами"
            )
        новая_запись = устойчивая_проекция_записи(запись)
        новая_запись["хэш_цели"] = хэш_байтов(данные)
        if (
            запись["действие_содержимого"] == "сохранить_байты"
            and новая_запись["хэш_цели"] != запись["хэш_источника"]
        ):
            raise ОшибкаКонтракта(
                f"Побайтовый выход изменяет источник: {запись['исходный_путь']}"
            )
        записи.append(новая_запись)
    итоговые_файлы = sorted(
        [*ожидаемые, план["путь_манифеста"]],
        key=lambda путь: путь.encode("utf-8"),
    )
    return {
        "схема": СХЕМА_МАНИФЕСТА,
        "хэш_плана": план["хэш_плана"],
        "хэш_политики": план["хэш_политики"],
        "исходный_снимок": копия_машинного_значения(план["исходный_снимок"]),
        "исходная_область": план["исходная_область"],
        "производное_пространство": план["производное_пространство"],
        "целевая_область": план["целевая_область"],
        "корень_файлов": план["корень_файлов"],
        "путь_манифеста": план["путь_манифеста"],
        "исключённые_префиксы": list(план["исключённые_префиксы"]),
        "преобразование": dict(план["преобразование"]),
        "форматная_политика": копия_машинного_значения(план["форматная_политика"]),
        "пустые_каталоги": план["пустые_каталоги"],
        "записи": записи,
        "итоговые_файлы": итоговые_файлы,
    }


def открыть_каталог_цели(корень: Path) -> int:
    if not hasattr(os, "O_NOFOLLOW") or not hasattr(os, "O_DIRECTORY"):
        raise ОшибкаКонтракта(
            "Платформа не предоставляет безопасное открытие каталога цели"
        )
    текущий_дескриптор = os.open(
        корень,
        os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
    )
    try:
        for компонент in PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ).parts:
            следующий_дескриптор = os.open(
                компонент,
                os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
                dir_fd=текущий_дескриптор,
            )
            сведения_компонента = os.fstat(следующий_дескриптор)
            if stat.S_IMODE(сведения_компонента.st_mode) != 0o755:
                os.close(следующий_дескриптор)
                raise ОшибкаКонтракта(
                    "Каждый компонент пути цели должен иметь режим 0755"
                )
            os.close(текущий_дескриптор)
            текущий_дескриптор = следующий_дескриптор
        return текущий_дескриптор
    except BaseException:
        os.close(текущий_дескриптор)
        raise


def снимок_целевого_дерева(
    корень: Path,
    каталог_поколения: Path | None = None,
    *,
    допустимые_режимы_корня: frozenset[int] = frozenset({0o755}),
) -> dict[str, Any]:
    try:
        if каталог_поколения is None:
            корневой_дескриптор = открыть_каталог_цели(корень)
            корневые_сведения = os.fstat(корневой_дескриптор)
            if stat.S_IMODE(корневые_сведения.st_mode) not in допустимые_режимы_корня:
                os.close(корневой_дескриптор)
                raise ОшибкаКонтракта(
                    "Корень поколения должен иметь режим 0755"
                )
        else:
            сведения = каталог_поколения.lstat()
            if stat.S_ISLNK(сведения.st_mode) or not stat.S_ISDIR(сведения.st_mode):
                raise ОшибкаКонтракта(
                    "Проверяемое поколение не является обычным каталогом"
                )
            if stat.S_IMODE(сведения.st_mode) not in допустимые_режимы_корня:
                raise ОшибкаКонтракта(
                    "Корень поколения должен иметь режим 0755"
                )
            корневой_дескриптор = os.open(
                каталог_поколения,
                os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
            )
    except ОшибкаКонтракта:
        raise
    except OSError as ошибка:
        raise ОшибкаКонтракта(
            "Целевая область отсутствует, недоступна или содержит символическую ссылку"
        ) from ошибка
    файлы: dict[str, dict[str, Any]] = {}
    каталоги: list[str] = []

    def обойти(дескриптор: int, префикс: str) -> None:
        try:
            элементы = sorted(os.scandir(дескриптор), key=lambda элемент: элемент.name.encode("utf-8"))
        except OSError as ошибка:
            raise ОшибкаКонтракта(
                f"Не удалось полностью прочитать целевой каталог: {префикс or '.'}"
            ) from ошибка
        for элемент in элементы:
            относительный = f"{префикс}/{элемент.name}" if префикс else элемент.name
            try:
                сведения = элемент.stat(follow_symlinks=False)
            except OSError as ошибка:
                raise ОшибкаКонтракта(
                    f"Не удалось получить сведения о целевом объекте: {относительный}"
                ) from ошибка
            if stat.S_ISLNK(сведения.st_mode):
                raise ОшибкаКонтракта(
                    f"Целевая область содержит символическую ссылку: {относительный}"
                )
            if stat.S_ISDIR(сведения.st_mode):
                if stat.S_IMODE(сведения.st_mode) != 0o755:
                    raise ОшибкаКонтракта(
                        f"Целевой каталог имеет неверный режим: {относительный}"
                    )
                каталоги.append(относительный)
                try:
                    дочерний_дескриптор = os.open(
                        элемент.name,
                        os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
                        dir_fd=дескриптор,
                    )
                except OSError as ошибка:
                    raise ОшибкаКонтракта(
                        f"Не удалось безопасно открыть целевой каталог: {относительный}"
                    ) from ошибка
                try:
                    обойти(дочерний_дескриптор, относительный)
                finally:
                    os.close(дочерний_дескриптор)
                continue
            if not stat.S_ISREG(сведения.st_mode):
                raise ОшибкаКонтракта(
                    f"Целевая область содержит специальный объект: {относительный}"
                )
            try:
                дескриптор_файла = os.open(
                    элемент.name,
                    os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK,
                    dir_fd=дескриптор,
                )
            except OSError as ошибка:
                raise ОшибкаКонтракта(
                    f"Не удалось безопасно открыть целевой файл: {относительный}"
                ) from ошибка
            try:
                сведения_до = os.fstat(дескриптор_файла)
                if not stat.S_ISREG(сведения_до.st_mode):
                    raise ОшибкаКонтракта(
                        f"Целевой файл подменён специальным объектом: {относительный}"
                    )
                части: list[bytes] = []
                вычислитель = hashlib.sha256()
                размер = 0
                while True:
                    часть = os.read(дескриптор_файла, 1024 * 1024)
                    if not часть:
                        break
                    вычислитель.update(часть)
                    размер += len(часть)
                    if относительный == PurePosixPath(ПУТЬ_МАНИФЕСТА).name:
                        части.append(часть)
                сведения_после = os.fstat(дескриптор_файла)
                if (
                    сведения_до.st_ino != сведения_после.st_ino
                    or сведения_до.st_size != сведения_после.st_size
                    or сведения_до.st_mtime_ns != сведения_после.st_mtime_ns
                    or сведения_до.st_mode != сведения_после.st_mode
                    or размер != сведения_после.st_size
                ):
                    raise ОшибкаКонтракта(
                        f"Целевой файл изменился во время чтения: {относительный}"
                    )
                точный_режим = stat.S_IMODE(сведения_после.st_mode)
                if точный_режим not in {0o644, 0o755}:
                    raise ОшибкаКонтракта(
                        f"Целевой файл имеет неверный точный режим: {относительный}"
                    )
                файлы[относительный] = {
                    "хэш": f"sha256:{вычислитель.hexdigest()}",
                    "режим": "100755" if точный_режим == 0o755 else "100644",
                    "размер": размер,
                    "байты": b"".join(части) if части else None,
                }
            finally:
                os.close(дескриптор_файла)

    try:
        обойти(корневой_дескриптор, "")
    finally:
        os.close(корневой_дескриптор)
    return {
        "каталоги": sorted(каталоги, key=lambda путь: путь.encode("utf-8")),
        "файлы": файлы,
    }


def устойчивый_снимок_дерева(снимок: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "каталоги": list(снимок["каталоги"]),
        "файлы": {
            путь: {
                "хэш": запись["хэш"],
                "режим": запись["режим"],
                "размер": запись["размер"],
            }
            for путь, запись in снимок["файлы"].items()
        },
    }


def хэш_дерева(снимок: Mapping[str, Any]) -> str:
    return хэш_значения(устойчивый_снимок_дерева(снимок))


def проверить_манифест_владения(
    политика: Mapping[str, Any],
    манифест: Mapping[str, Any],
) -> tuple[dict[str, Mapping[str, Any]], list[str]]:
    if not isinstance(манифест, Mapping):
        raise ОшибкаКонтракта("Манифест поколения обязан быть JSON-объектом")
    потребовать_поля(манифест, ПОЛЯ_МАНИФЕСТА, "манифест")
    if манифест["схема"] != СХЕМА_МАНИФЕСТА:
        raise ОшибкаКонтракта("Неподдержанная схема манифеста поколения")
    хэш_политики = хэш_значения(политика)
    if манифест["хэш_политики"] != хэш_политики:
        raise ОшибкаКонтракта("Прежний манифест не принадлежит действующей политике")
    проверить_хэш(манифест["хэш_плана"], "манифест.хэш_плана")
    исходный_снимок = манифест["исходный_снимок"]
    if not isinstance(исходный_снимок, Mapping):
        raise ОшибкаКонтракта("Манифест содержит неверный исходный снимок")
    потребовать_поля(
        исходный_снимок,
        {"хэш_инвентаря", "хэш_политики"},
        "манифест.исходный_снимок",
    )
    проверить_хэш(
        исходный_снимок["хэш_инвентаря"],
        "манифест.исходный_снимок.хэш_инвентаря",
    )
    проверить_хэш(
        исходный_снимок["хэш_политики"],
        "манифест.исходный_снимок.хэш_политики",
    )
    if исходный_снимок["хэш_политики"] != хэш_политики:
        raise ОшибкаКонтракта(
            "Исходный снимок манифеста имеет чужой хэш политики"
        )
    точные_поля = {
        "исходная_область": ".",
        "производное_пространство": ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
        "целевая_область": ЦЕЛЕВАЯ_ОБЛАСТЬ,
        "корень_файлов": КОРЕНЬ_ФАЙЛОВ,
        "путь_манифеста": ПУТЬ_МАНИФЕСТА,
        "исключённые_префиксы": политика["исключённые_префиксы"],
        "преобразование": политика["преобразование"],
        "форматная_политика": политика["форматы"],
        "пустые_каталоги": политика["пустые_каталоги"],
    }
    for поле, ожидаемое in точные_поля.items():
        if канонические_байты(манифест[поле]) != канонические_байты(ожидаемое):
            raise ОшибкаКонтракта(
                f"Прежний манифест имеет чужое поле {поле}"
            )
    записи = манифест["записи"]
    if not isinstance(записи, list):
        raise ОшибкаКонтракта("Манифест поколения не содержит массив записей")
    по_целям: dict[str, Mapping[str, Any]] = {}
    исходники: set[str] = set()
    порядок_исходников: list[str] = []
    for запись in записи:
        if not isinstance(запись, Mapping):
            raise ОшибкаКонтракта("Манифест поколения содержит не-объект")
        потребовать_поля(
            запись,
            ПОЛЯ_ЗАПИСИ_МАНИФЕСТА,
            "запись манифеста",
        )
        источник = проверить_относительный_путь(
            запись["исходный_путь"],
            "манифест.исходный_путь",
        )
        цель = проверить_относительный_путь(
            запись["целевой_путь"],
            "манифест.целевой_путь",
        )
        if not путь_под_префиксом(цель, КОРЕНЬ_ФАЙЛОВ):
            raise ОшибкаКонтракта(
                f"Манифест объявляет цель вне корня файлов: {цель}"
            )
        if источник in исходники or цель in по_целям:
            raise ОшибкаКонтракта(
                "Манифест повторяет исходный или целевой путь"
            )
        исходники.add(источник)
        порядок_исходников.append(источник)
        по_целям[цель] = запись
        if запись["тип"] != "обычный_файл":
            raise ОшибкаКонтракта(
                f"Манифест объявляет неподдерживаемый тип источника: {источник}"
            )
        проверить_хэш(запись["хэш_источника"], f"хэш источника {источник}")
        проверить_хэш(запись["хэш_цели"], f"хэш цели {цель}")
        if запись["режим"] not in {"100644", "100755"}:
            raise ОшибкаКонтракта(f"Недопустимый режим цели: {цель}")
        размер = запись["размер_источника"]
        if type(размер) is not int or размер < 0:
            raise ОшибкаКонтракта(
                f"Манифест содержит неверный размер источника: {источник}"
            )
        for поле in ("класс_содержимого", "причина_действия"):
            if not isinstance(запись[поле], str) or not запись[поле]:
                raise ОшибкаКонтракта(
                    f"Манифест содержит неверное поле {поле}: {источник}"
                )
        if запись["действие_содержимого"] not in {
            "сохранить_байты",
            "преобразовать_структурно",
            "преобразовать_разметку_с_дословным_блоком",
        }:
            raise ОшибкаКонтракта(
                f"Манифест содержит неизвестное действие: {источник}"
            )
        компоненты = запись["компоненты_пути"]
        if not isinstance(компоненты, list) or not компоненты:
            raise ОшибкаКонтракта(
                f"Манифест содержит неверные компоненты пути: {источник}"
            )
        исходные_компоненты: list[str] = []
        целевые_компоненты: list[str] = []
        for компонент in компоненты:
            if not isinstance(компонент, Mapping):
                raise ОшибкаКонтракта(
                    f"Компонент пути манифеста не является объектом: {источник}"
                )
            потребовать_поля(
                компонент,
                {
                    "исходный",
                    "целевая_основа",
                    "сохранённое_расширение",
                    "целевой",
                    "изменён",
                },
                "компонент пути манифеста",
            )
            for поле in (
                "исходный",
                "целевая_основа",
                "сохранённое_расширение",
                "целевой",
            ):
                if not isinstance(компонент[поле], str):
                    raise ОшибкаКонтракта(
                        f"Компонент пути содержит нестроковое поле {поле}: {источник}"
                    )
            if (
                not компонент["исходный"]
                or not компонент["целевая_основа"]
                or not компонент["целевой"]
            ):
                raise ОшибкаКонтракта(
                    f"Компонент пути манифеста пуст: {источник}"
                )
            if type(компонент["изменён"]) is not bool:
                raise ОшибкаКонтракта(
                    f"Компонент пути содержит неверный признак изменения: {источник}"
                )
            if компонент["целевой"] != (
                компонент["целевая_основа"]
                + компонент["сохранённое_расширение"]
            ):
                raise ОшибкаКонтракта(
                    f"Компонент пути не восстанавливает целевое имя: {источник}"
                )
            if компонент["изменён"] != (
                компонент["целевой"] != компонент["исходный"]
            ):
                raise ОшибкаКонтракта(
                    f"Компонент пути имеет ложный признак изменения: {источник}"
                )
            проверить_переносимость_компонента(
                компонент["целевой"],
                политика["ограничения_пути"],
                источник,
            )
            исходные_компоненты.append(компонент["исходный"])
            целевые_компоненты.append(компонент["целевой"])
        if исходные_компоненты != источник.split("/"):
            raise ОшибкаКонтракта(
                f"Компоненты пути не восстанавливают источник: {источник}"
            )
        целевой_суффикс = list(
            PurePosixPath(цель)
            .relative_to(PurePosixPath(КОРЕНЬ_ФАЙЛОВ))
            .parts
        )
        if целевые_компоненты != целевой_суффикс:
            raise ОшибкаКонтракта(
                f"Компоненты пути не восстанавливают цель: {цель}"
            )
        if (
            запись["действие_содержимого"] == "сохранить_байты"
            and запись["хэш_источника"] != запись["хэш_цели"]
        ):
            raise ОшибкаКонтракта(
                f"Побайтовый выход прежнего манифеста изменён: {цель}"
            )
    if порядок_исходников != sorted(
        порядок_исходников,
        key=lambda путь: путь.encode("utf-8"),
    ):
        raise ОшибкаКонтракта(
            "Записи манифеста нарушают канонический порядок исходных путей"
        )
    итоговые = манифест["итоговые_файлы"]
    if not isinstance(итоговые, list) or not all(
        isinstance(путь, str) for путь in итоговые
    ):
        raise ОшибкаКонтракта("Манифест содержит некорректный итоговый набор")
    ожидаемые = sorted(
        [*по_целям, ПУТЬ_МАНИФЕСТА],
        key=lambda путь: путь.encode("utf-8"),
    )
    if итоговые != ожидаемые:
        raise ОшибкаКонтракта(
            "Итоговый набор прежнего манифеста не совпадает с его записями"
        )
    смысловые_записи: list[dict[str, Any]] = []
    for запись in записи:
        смысловая_запись = копия_машинного_значения(запись)
        смысловая_запись["хэш_цели"] = None
        смысловые_записи.append(смысловая_запись)
    восстановленный_план = {
        "схема": СХЕМА_ПЛАНА,
        "хэш_плана": манифест["хэш_плана"],
        "исходный_снимок": копия_машинного_значения(исходный_снимок),
        "хэш_политики": манифест["хэш_политики"],
        "исходная_область": манифест["исходная_область"],
        "производное_пространство": манифест["производное_пространство"],
        "целевая_область": манифест["целевая_область"],
        "корень_файлов": манифест["корень_файлов"],
        "путь_манифеста": манифест["путь_манифеста"],
        "исключённые_префиксы": копия_машинного_значения(
            манифест["исключённые_префиксы"]
        ),
        "преобразование": копия_машинного_значения(
            манифест["преобразование"]
        ),
        "форматная_политика": копия_машинного_значения(
            манифест["форматная_политика"]
        ),
        "пустые_каталоги": манифест["пустые_каталоги"],
        "полный_инвентарь": [],
        "записи": смысловые_записи,
        "итоговые_целевые_пути": sorted(
            по_целям,
            key=lambda путь: путь.encode("utf-8"),
        ),
        "состояние": "готов_без_записи",
    }
    if вычислить_хэш_плана(восстановленный_план) != манифест["хэш_плана"]:
        raise ОшибкаКонтракта(
            "Манифест не восстанавливает закреплённый хэш смыслового плана"
        )
    return по_целям, ожидаемые


def проверить_дерево_по_манифесту(
    корень: Path,
    каталог: Path,
    политика: Mapping[str, Any],
    манифест: Mapping[str, Any] | None = None,
) -> tuple[dict[str, Any], dict[str, Any]]:
    путь_манифеста = каталог / PurePosixPath(ПУТЬ_МАНИФЕСТА).name
    if манифест is None:
        try:
            сведения_манифеста = путь_манифеста.lstat()
        except FileNotFoundError as ошибка:
            raise ОшибкаКонтракта(
                "неуправляемая целевая область: отсутствует манифест поколения"
            ) from ошибка
        if stat.S_ISLNK(сведения_манифеста.st_mode) or not stat.S_ISREG(
            сведения_манифеста.st_mode
        ):
            raise ОшибкаКонтракта(
                "Неуправляемая целевая область: манифест подменён специальным объектом"
            )
        манифест = загрузить_машинные_данные(
            путь_манифеста,
            "манифест поколения",
        )
    по_целям, итоговые = проверить_манифест_владения(политика, манифест)
    if каталог == корень / PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ):
        снимок = снимок_целевого_дерева(корень)
    else:
        снимок = снимок_целевого_дерева(корень, каталог)
    ожидаемые_относительные = {
        PurePosixPath(путь)
        .relative_to(PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ))
        .as_posix()
        for путь in итоговые
    }
    фактические = set(снимок["файлы"])
    if фактические != ожидаемые_относительные:
        raise ОшибкаКонтракта(
            "Целевая область содержит отсутствующий или неизвестный файл; "
            f"отсутствуют={sorted(ожидаемые_относительные - фактические)}, "
            f"лишние={sorted(фактические - ожидаемые_относительные)}"
        )
    ожидаемые_каталоги: set[str] = set()
    for относительный in ожидаемые_относительные:
        части = PurePosixPath(относительный).parts
        for глубина in range(1, len(части)):
            ожидаемые_каталоги.add("/".join(части[:глубина]))
    if set(снимок["каталоги"]) != ожидаемые_каталоги:
        raise ОшибкаКонтракта(
            "Целевая область содержит отсутствующий или неизвестный каталог"
        )
    относительный_манифест = PurePosixPath(ПУТЬ_МАНИФЕСТА).name
    запись_манифеста = снимок["файлы"][относительный_манифест]
    if запись_манифеста["байты"] != канонические_байты(манифест):
        raise ОшибкаКонтракта(
            "Байты манифеста не совпадают с каноническим проверяемым объектом"
        )
    if запись_манифеста["режим"] != "100644":
        raise ОшибкаКонтракта("Манифест поколения не должен быть исполняемым")
    for полный_путь, запись in по_целям.items():
        относительный = (
            PurePosixPath(полный_путь)
            .relative_to(PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ))
            .as_posix()
        )
        фактическая = снимок["файлы"][относительный]
        if фактическая["хэш"] != запись["хэш_цели"]:
            raise ОшибкаКонтракта(
                f"хэш целевого файла не совпадает: {полный_путь}"
            )
        if фактическая["режим"] != запись["режим"]:
            raise ОшибкаКонтракта(
                f"Режим целевого файла не совпадает: {полный_путь}"
            )
    return dict(манифест), снимок


def проверить_производное_пространство(
    корень: Path,
    политика: Mapping[str, Any],
    *,
    разрешить_служебный_каталог: bool = False,
) -> dict[str, Any] | None:
    пространство = корень / ПРОИЗВОДНОЕ_ПРОСТРАНСТВО
    проверить_точное_имя_дочернего_пути(
        корень, ПРОИЗВОДНОЕ_ПРОСТРАНСТВО, "производного пространства"
    )
    сведения = получить_сведения_без_перехода(
        пространство,
        "производного пространства",
    )
    if stat.S_ISLNK(сведения.st_mode) or not stat.S_ISDIR(сведения.st_mode):
        raise ОшибкаКонтракта(
            "Символическая ссылка или специальный объект подменили производное пространство"
        )
    if stat.S_IMODE(сведения.st_mode) != 0o755:
        raise ОшибкаКонтракта(
            "Производное пространство должно иметь режим 0755"
        )
    допустимые = {PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ).name}
    if разрешить_служебный_каталог:
        допустимые.add(PurePosixPath(СЛУЖЕБНЫЙ_КАТАЛОГ).name)
    try:
        имена = {элемент.name for элемент in os.scandir(пространство)}
    except OSError as ошибка:
        raise ОшибкаКонтракта(
            "Не удалось полностью прочитать производное пространство"
        ) from ошибка
    лишние = имена - допустимые
    if лишние:
        raise ОшибкаКонтракта(
            "Неуправляемая целевая область закрывает замену: "
            + ", ".join(sorted(лишние))
        )
    служебный = пространство / PurePosixPath(СЛУЖЕБНЫЙ_КАТАЛОГ).name
    if служебный.exists() and not разрешить_служебный_каталог:
        raise ОшибкаКонтракта(
            "Обнаружена незавершённая установка; требуется повторить применение"
        )
    цель = корень / PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
    if not цель.exists():
        if разрешить_служебный_каталог and служебный.exists():
            return None
        raise ОшибкаКонтракта(
            "Неуправляемая целевая область не содержит подтверждённого поколения"
        )
    манифест, _снимок = проверить_дерево_по_манифесту(
        корень,
        цель,
        политика,
    )
    return манифест


def снимок_конфликтного_поколения(
    корень: Path,
    политика: Mapping[str, Any],
) -> dict[str, Any] | None:
    пространство = корень / ПРОИЗВОДНОЕ_ПРОСТРАНСТВО
    цель = корень / PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
    try:
        сведения = пространство.lstat()
    except FileNotFoundError:
        return None
    проверить_точное_имя_дочернего_пути(
        корень, ПРОИЗВОДНОЕ_ПРОСТРАНСТВО, "корня конфликтной проекции"
    )
    if (
        stat.S_ISLNK(сведения.st_mode)
        or not stat.S_ISDIR(сведения.st_mode)
        or stat.S_IMODE(сведения.st_mode) != 0o755
    ):
        raise ОшибкаКонтракта(
            "Корень конфликтной проекции подменён или имеет неверный режим"
        )
    try:
        with os.scandir(пространство) as элементы:
            имена = {элемент.name for элемент in элементы}
    except OSError as ошибка:
        raise ОшибкаКонтракта(
            "Не удалось прочитать конфликтное производное пространство"
        ) from ошибка
    ожидаемое_имя = PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ).name
    if not имена:
        return None
    if имена != {ожидаемое_имя}:
        raise ОшибкаКонтракта(
            "Конфликтное производное пространство содержит неуправляемый объект"
        )
    снимок = снимок_целевого_дерева(корень, цель)
    стадии_индекса = прочитать_стадии_индекса_проекции(корень)
    конфликтные_пути = {
        путь
        for путь, стадии in стадии_индекса.items()
        if any(стадия != "0" for стадия in стадии)
    }
    if not конфликтные_пути:
        raise ОшибкаКонтракта(
            "Конфликтное поколение не подтверждено стадиями Git-индекса"
        )
    проверить_происхождение_стадий_слияния(корень, стадии_индекса)

    стадии_манифеста = стадии_индекса.get(ПУТЬ_МАНИФЕСТА, {})
    if not стадии_манифеста:
        raise ОшибкаКонтракта(
            "Конфликтное поколение не имеет манифеста владения в Git-индексе"
        )
    доверенные_стадии_манифеста = {
        стадия: запись
        for стадия, запись in стадии_манифеста.items()
        if стадия != "0"
    }
    if not доверенные_стадии_манифеста:
        raise ОшибкаКонтракта(
            "Конфликтное поколение не имеет доверенной "
            "конфликтной стадии манифеста"
        )
    разрешённые_пути: set[str] = set()
    разрешённые_версии: dict[str, set[tuple[str, str]]] = {}
    версии_по_стадиям: dict[str, dict[str, tuple[str, str]]] = {}
    for стадия, запись_индекса in sorted(
        доверенные_стадии_манифеста.items()
    ):
        if запись_индекса["режим"] != "100644":
            raise ОшибкаКонтракта(
                f"Конфликтный манифест имеет неверный режим в стадии {стадия}"
            )
        сырые_байты = выполнить_команду_контроля_версий(
            корень,
            "cat-file",
            "blob",
            запись_индекса["идентификатор_объекта_репозитория"],
            двоичный=True,
        )
        assert isinstance(сырые_байты, bytes)
        манифест = разобрать_машинные_данные(
            сырые_байты,
            f"манифест поколения в стадии {стадия}",
        )
        if канонические_байты(манифест) != сырые_байты:
            raise ОшибкаКонтракта(
                f"Стадия {стадия} содержит неканонический манифест поколения"
            )
        по_целям, итоговые = проверить_манифест_владения(
            политика,
            манифест,
        )
        разрешённые_пути.update(итоговые)
        версии_стадии = {
            ПУТЬ_МАНИФЕСТА: ("100644", хэш_байтов(сырые_байты))
        }
        for путь, запись in по_целям.items():
            версии_стадии[путь] = (запись["режим"], запись["хэш_цели"])
        версии_по_стадиям[стадия] = версии_стадии
        for путь, версия in версии_стадии.items():
            разрешённые_версии.setdefault(путь, set()).add(версия)

    индексные_пути = set(стадии_индекса)
    неизвестные_индексные = индексные_пути - разрешённые_пути
    if неизвестные_индексные:
        raise ОшибкаКонтракта(
            "Конфликтное поколение содержит неизвестный индексный путь: "
            + ", ".join(sorted(неизвестные_индексные))
        )
    отсутствующие_индексные = разрешённые_пути - индексные_пути
    if отсутствующие_индексные:
        raise ОшибкаКонтракта(
            "Конфликтное поколение потеряло ожидаемый индексный путь: "
            + ", ".join(sorted(отсутствующие_индексные))
        )
    версии_нулевой_стадии: dict[str, tuple[str, str]] = {}
    for путь, стадии in sorted(стадии_индекса.items()):
        for стадия, запись_индекса in sorted(стадии.items()):
            сырые_байты = выполнить_команду_контроля_версий(
                корень,
                "cat-file",
                "blob",
                запись_индекса["идентификатор_объекта_репозитория"],
                двоичный=True,
            )
            assert isinstance(сырые_байты, bytes)
            версия = (запись_индекса["режим"], хэш_байтов(сырые_байты))
            if стадия == "0":
                ожидаемые = разрешённые_версии.get(путь, set())
                версии_нулевой_стадии[путь] = версия
            else:
                ожидаемая_версия = версии_по_стадиям.get(стадия, {}).get(путь)
                ожидаемые = set() if ожидаемая_версия is None else {ожидаемая_версия}
            if версия not in ожидаемые:
                raise ОшибкаКонтракта(
                    "Конфликтное поколение содержит индексный дрейф известного пути: "
                    f"{путь}, стадия {стадия}"
                )
    относительный_корень = PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
    фактические_файлы = {
        (относительный_корень / PurePosixPath(путь)).as_posix()
        for путь in снимок["файлы"]
    }
    неизвестные_файлы = фактические_файлы - разрешённые_пути
    if неизвестные_файлы:
        raise ОшибкаКонтракта(
            "Конфликтное поколение содержит неизвестный файл: "
            + ", ".join(sorted(неизвестные_файлы))
        )
    файлы_без_индекса = фактические_файлы - индексные_пути
    if файлы_без_индекса:
        raise ОшибкаКонтракта(
            "Конфликтное поколение содержит известный файл, "
            "который не имеет записи Git-индекса: "
            + ", ".join(sorted(файлы_без_индекса))
        )
    for путь, индексная_версия in версии_нулевой_стадии.items():
        относительный = PurePosixPath(путь).relative_to(
            PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
        ).as_posix()
        фактическая = снимок["файлы"].get(относительный)
        if фактическая is None:
            raise ОшибкаКонтракта(
                "Конфликтное поколение потеряло неконфликтный файл: "
                + путь
            )
        фактическая_версия = (фактическая["режим"], фактическая["хэш"])
        if фактическая_версия != индексная_версия:
            raise ОшибкаКонтракта(
                "Конфликтное поколение содержит ручной дрейф "
                "неконфликтного файла относительно Git-индекса: "
                + путь
            )
    разрешённые_каталоги: set[str] = set()
    for путь in разрешённые_пути:
        предок = PurePosixPath(путь).parent
        while путь_под_префиксом(предок.as_posix(), ЦЕЛЕВАЯ_ОБЛАСТЬ):
            разрешённые_каталоги.add(предок.as_posix())
            if предок.as_posix() == ЦЕЛЕВАЯ_ОБЛАСТЬ:
                break
            предок = предок.parent
    фактические_каталоги = {
        (относительный_корень / PurePosixPath(путь)).as_posix()
        for путь in снимок["каталоги"]
    }
    неизвестные_каталоги = фактические_каталоги - разрешённые_каталоги
    if неизвестные_каталоги:
        raise ОшибкаКонтракта(
            "Конфликтное поколение содержит неизвестный каталог: "
            + ", ".join(sorted(неизвестные_каталоги))
        )

    проверить_неизменность_рабочих_конфликтов(корень, снимок)

    сырые_изменённые = выполнить_команду_контроля_версий(
        корень,
        "diff-files",
        "--name-only",
        "-z",
        "--",
        ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
        двоичный=True,
    )
    assert isinstance(сырые_изменённые, bytes)
    try:
        изменённые = {
            путь.decode("utf-8")
            for путь in сырые_изменённые.split(b"\0")
            if путь
        }
    except UnicodeError as ошибка:
        raise ОшибкаКонтракта(
            "Git вернул неподдержанное имя дрейфа проекции"
        ) from ошибка
    неконфликтный_дрейф = изменённые - конфликтные_пути
    if неконфликтный_дрейф:
        raise ОшибкаКонтракта(
            "Конфликтное поколение содержит ручной дрейф вне конфликтных путей: "
            + ", ".join(sorted(неконфликтный_дрейф))
        )
    return снимок


def синхронизировать_каталог(путь: Path) -> None:
    дескриптор = os.open(путь, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def атомарно_переименовать_без_замены(
    источник: Path,
    назначение: Path,
) -> None:
    """Атомарно переносит путь только в отсутствующее назначение."""

    исходные_байты = os.fsencode(источник)
    целевые_байты = os.fsencode(назначение)
    try:
        if sys.platform == "darwin":
            библиотека = ctypes.CDLL(None, use_errno=True)
            функция = библиотека.renamex_np
            setattr(
                функция,
                "argtypes",
                [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint],
            )
            setattr(функция, "restype", ctypes.c_int)
            результат = функция(исходные_байты, целевые_байты, 0x00000004)
        elif sys.platform.startswith("linux"):
            библиотека = ctypes.CDLL(None, use_errno=True)
            функция = библиотека.renameat2
            setattr(
                функция,
                "argtypes",
                [
                    ctypes.c_int,
                    ctypes.c_char_p,
                    ctypes.c_int,
                    ctypes.c_char_p,
                    ctypes.c_uint,
                ],
            )
            setattr(функция, "restype", ctypes.c_int)
            результат = функция(
                -100,
                исходные_байты,
                -100,
                целевые_байты,
                0x00000001,
            )
        elif os.name == "nt":
            os.rename(источник, назначение)
            return
        else:
            raise ОшибкаКонтракта(
                "Платформа не предоставляет атомарное переименование без замены"
            )
    except AttributeError as ошибка:
        raise ОшибкаКонтракта(
            "Платформа не предоставляет атомарное переименование без замены"
        ) from ошибка
    except FileExistsError as ошибка:
        raise ОшибкаКонтракта(
            f"Назначение атомарного переноса уже существует: {назначение}"
        ) from ошибка
    if результат != 0:
        номер = ctypes.get_errno()
        ошибка = OSError(номер, os.strerror(номер), назначение)
        if номер in {errno.EEXIST, errno.ENOTEMPTY}:
            raise ОшибкаКонтракта(
                f"Назначение атомарного переноса уже существует: {назначение}"
            ) from ошибка
        raise ОшибкаКонтракта(
            f"Не удалось атомарно перенести {источник} в {назначение}"
        ) from ошибка



def записать_обычный_файл(
    путь: Path,
    данные: bytes,
    режим: str,
) -> None:
    флаги = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    if hasattr(os, "O_NOFOLLOW"):
        флаги |= os.O_NOFOLLOW
    дескриптор = os.open(путь, флаги, 0o600)
    try:
        позиция = 0
        while позиция < len(данные):
            записано = os.write(дескриптор, данные[позиция:])
            if записано <= 0:
                raise ОшибкаКонтракта(f"Не удалось полностью записать файл: {путь}")
            позиция += записано
        os.fsync(дескриптор)
        os.fchmod(дескриптор, 0o755 if режим == "100755" else 0o644)
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)



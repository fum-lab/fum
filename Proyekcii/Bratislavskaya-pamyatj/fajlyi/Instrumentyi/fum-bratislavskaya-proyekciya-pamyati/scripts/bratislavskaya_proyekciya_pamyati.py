def очистить_доказанный_частичный_журнал(
    корень: Path,
    служебный: Path,
    квитанция: Mapping[str, Any],
    свидетельство_квитанции: tuple[int, int, int, int, int],
) -> None:
    имя = имя_временного_состояния(str(квитанция["транзакция"]))
    путь = служебный / имя
    try:
        сведения = путь.lstat()
    except FileNotFoundError:
        return
    проверить_точное_имя_дочернего_пути(служебный, имя, "частичного журнала")
    режим = stat.S_IMODE(сведения.st_mode)
    if stat.S_ISLNK(сведения.st_mode) or not stat.S_ISREG(сведения.st_mode) or режим not in {0o600, 0o644}:
        raise ОшибкаКонтракта("Частичный журнал подменён")
    данные = прочитать_точный_обычный_файл(
        путь,
        "частичный журнал установки",
        режим=режим,
    )
    фазы = (
        "строится",
        "подготовлено",
        "прежнее_зарезервировано",
        "новое_установлено",
        "принято",
        "откачено",
    )
    кандидаты = [
        канонические_байты(базовое_состояние_из_квитанции(квитанция, фаза))
        for фаза in фазы
    ]
    if (
        (режим == 0o644 and данные not in кандидаты)
        or (режим == 0o600 and not any(кандидат.startswith(данные) for кандидат in кандидаты))
    ):
        raise ОшибкаКонтракта("Частичный журнал не принадлежит квитанции")
    свидетельство = (
        сведения.st_dev,
        сведения.st_ino,
        сведения.st_mode,
        сведения.st_size,
        сведения.st_mtime_ns,
    )
    проверить_неизменность_квитанции(корень, квитанция, свидетельство_квитанции)
    текущие = путь.lstat()
    if свидетельство != (текущие.st_dev, текущие.st_ino, текущие.st_mode, текущие.st_size, текущие.st_mtime_ns):
        raise ОшибкаКонтракта("Частичный журнал изменился перед очисткой")
    путь.unlink()
    синхронизировать_каталог(служебный)


def очистить_доказанную_частичную_запись(
    корень: Path,
    служебный: Path,
    квитанция: Mapping[str, Any],
    свидетельство_квитанции: tuple[int, int, int, int, int],
) -> None:
    имя = имя_каталога_частичной_записи(str(квитанция["транзакция"]))
    каталог = служебный / имя
    try:
        сведения_каталога = каталог.lstat()
    except FileNotFoundError:
        return
    проверить_точное_имя_дочернего_пути(служебный, имя, "каталога частичной записи")
    if stat.S_ISLNK(сведения_каталога.st_mode) or not stat.S_ISDIR(сведения_каталога.st_mode) or stat.S_IMODE(сведения_каталога.st_mode) != 0o700:
        raise ОшибкаКонтракта("Каталог частичной записи подменён")
    ожидаемые: dict[str, Mapping[str, Any]] = {}
    for относительный, запись in квитанция["новый_снимок"]["файлы"].items():
        имя_файла = hashlib.sha256(относительный.encode("utf-8")).hexdigest() + ".tmp"
        if имя_файла in ожидаемые:
            raise ОшибкаКонтракта("Хэш-коллизия имён частичной записи")
        ожидаемые[имя_файла] = запись
    свидетельства: dict[Path, tuple[int, int, int, int, int]] = {}
    for элемент in sorted(os.scandir(каталог), key=lambda запись: запись.name.encode("utf-8")):
        путь = каталог / элемент.name
        сведения = элемент.stat(follow_symlinks=False)
        ожидаемая = ожидаемые.get(элемент.name)
        режим = stat.S_IMODE(сведения.st_mode)
        допустимые_режимы = {
            0o600,
            0o755
            if ожидаемая and ожидаемая["режим"] == "100755"
            else 0o644,
        }
        if (
            ожидаемая is None
            or not stat.S_ISREG(сведения.st_mode)
            or режим not in допустимые_режимы
            or сведения.st_size > ожидаемая["размер"]
        ):
            raise ОшибкаКонтракта(f"Неизвестный объект в частичной записи: {элемент.name}")
        данные = прочитать_точный_обычный_файл(
            путь,
            f"частичный файл {элемент.name}",
            режим=режим,
        )
        if режим != 0o600 and (
            len(данные) != ожидаемая["размер"]
            or хэш_байтов(данные) != ожидаемая["хэш"]
        ):
            raise ОшибкаКонтракта(
                f"Завершённый временный файл не совпал с квитанцией: {элемент.name}"
            )
        после = путь.lstat()
        свидетельства[путь] = (
            после.st_dev,
            после.st_ino,
            после.st_mode,
            после.st_size,
            после.st_mtime_ns,
        )
    for путь, свидетельство in свидетельства.items():
        проверить_неизменность_квитанции(корень, квитанция, свидетельство_квитанции)
        текущие = путь.lstat()
        if свидетельство != (текущие.st_dev, текущие.st_ino, текущие.st_mode, текущие.st_size, текущие.st_mtime_ns):
            raise ОшибкаКонтракта(f"Частичный файл изменился перед очисткой: {путь.name}")
        путь.unlink()
    проверить_неизменность_квитанции(корень, квитанция, свидетельство_квитанции)
    try:
        каталог.rmdir()
    except OSError as ошибка:
        raise ОшибкаКонтракта("Каталог частичной записи изменился перед очисткой") from ошибка
    синхронизировать_каталог(служебный)


def удалить_служебные_метаданные(
    корень: Path,
    пространство: Path,
    служебный: Path,
    квитанция: Mapping[str, Any],
    свидетельство_квитанции: tuple[int, int, int, int, int],
    *,
    удалить_пустое_пространство: bool,
) -> None:
    for имя in (
        "состояние.json",
        имя_временного_состояния(str(квитанция["транзакция"])),
    ):
        путь = служебный / имя
        try:
            путь.lstat()
        except FileNotFoundError:
            continue
        прочитать_состояние_установки(
            путь,
            квитанция,
            f"служебный файл {имя}",
        )
        проверить_неизменность_квитанции(
            корень,
            квитанция,
            свидетельство_квитанции,
        )
        путь.unlink()
    проверить_неизменность_квитанции(
        корень,
        квитанция,
        свидетельство_квитанции,
    )
    try:
        служебный.rmdir()
    except OSError as ошибка:
        raise ОшибкаКонтракта(
            "Служебный каталог не пуст после точной очистки"
        ) from ошибка
    синхронизировать_каталог(пространство)
    if удалить_пустое_пространство:
        try:
            пространство.rmdir()
        except OSError as ошибка:
            raise ОшибкаКонтракта(
                "Производное пространство не пусто после отката"
            ) from ошибка
        синхронизировать_каталог(корень)
    удалить_квитанцию_установки(
        корень,
        квитанция,
        свидетельство_квитанции,
    )


def восстановить_незавершённую_установку(
    корень: Path,
    политика: Mapping[str, Any],
) -> None:
    _ = политика
    пространство = корень / ПРОИЗВОДНОЕ_ПРОСТРАНСТВО
    служебный = корень / PurePosixPath(СЛУЖЕБНЫЙ_КАТАЛОГ)
    цель = корень / PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
    прочитанная_квитанция = прочитать_квитанцию_установки(корень)
    try:
        сведения_пространства = пространство.lstat()
    except FileNotFoundError:
        if прочитанная_квитанция is not None:
            _путь, квитанция, свидетельство_квитанции = прочитанная_квитанция
            if квитанция["была_цель"]:
                raise ОшибкаКонтракта(
                    "Квитанция прежней цели потеряла производное пространство"
                )
            синхронизировать_каталог(корень)
            удалить_квитанцию_установки(
                корень,
                квитанция,
                свидетельство_квитанции,
            )
        return
    проверить_точное_имя_дочернего_пути(
        корень,
        ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
        "производного пространства восстановления",
    )
    if stat.S_ISLNK(сведения_пространства.st_mode) or not stat.S_ISDIR(
        сведения_пространства.st_mode
    ) or stat.S_IMODE(сведения_пространства.st_mode) != 0o755:
        raise ОшибкаКонтракта("Производное пространство подменено или имеет неверный режим")
    имена_пространства = {элемент.name for элемент in os.scandir(пространство)}
    допустимые_имена_пространства = {
        PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ).name,
        PurePosixPath(СЛУЖЕБНЫЙ_КАТАЛОГ).name,
    }
    if not имена_пространства <= допустимые_имена_пространства:
        raise ОшибкаКонтракта(
            "Производное пространство восстановления содержит неизвестный объект"
        )
    try:
        сведения_служебного = служебный.lstat()
    except FileNotFoundError:
        квитанция_без_служебного: dict[str, Any] | None = None
        if прочитанная_квитанция is not None:
            _путь, квитанция, свидетельство_квитанции = прочитанная_квитанция
            квитанция_без_служебного = квитанция
            класс_цели, _снимок = классифицировать_фактическую_цель(
                корень,
                цель,
                квитанция,
            )
            допустимые_классы = (
                {"прежняя", "новая"}
                if квитанция["была_цель"]
                else {"отсутствует", "новая"}
            )
            if класс_цели not in допустимые_классы:
                raise ОшибкаКонтракта(
                    "Квитанция без служебного каталога не доказывает цель"
                )
        if (
            not имена_пространства
            and квитанция_без_служебного is not None
        ):
            проверить_неизменность_квитанции(
                корень,
                квитанция_без_служебного,
                свидетельство_квитанции,
            )
            пространство.rmdir()
            синхронизировать_каталог(корень)
        if квитанция_без_служебного is not None:
            if пространство.exists():
                синхронизировать_каталог(пространство)
            удалить_квитанцию_установки(
                корень,
                квитанция_без_служебного,
                свидетельство_квитанции,
            )
        return
    проверить_точное_имя_дочернего_пути(
        пространство,
        PurePosixPath(СЛУЖЕБНЫЙ_КАТАЛОГ).name,
        "служебного каталога восстановления",
    )
    if stat.S_ISLNK(сведения_служебного.st_mode) or not stat.S_ISDIR(
        сведения_служебного.st_mode
    ) or stat.S_IMODE(сведения_служебного.st_mode) != 0o700:
        raise ОшибкаКонтракта("Служебный путь установки подменён или имеет неверный режим")
    if прочитанная_квитанция is None:
        raise ОшибкаКонтракта(
            "Служебный каталог не имеет внешней квитанции владения"
        )
    (
        _путь_квитанции,
        квитанция,
        свидетельство_квитанции,
    ) = прочитанная_квитанция
    новое = служебный / "новое"
    прежнее = служебный / "прежнее"
    удаляемое = служебный / "удаляемое"
    путь_состояния = служебный / "состояние.json"
    очистить_доказанный_частичный_журнал(
        корень,
        служебный,
        квитанция,
        свидетельство_квитанции,
    )
    очистить_доказанную_частичную_запись(
        корень,
        служебный,
        квитанция,
        свидетельство_квитанции,
    )
    допустимые_служебные = {
        "состояние.json",
        "новое",
        "прежнее",
        "удаляемое",
    }
    фактические_служебные = {элемент.name for элемент in os.scandir(служебный)}
    if not фактические_служебные <= допустимые_служебные:
        raise ОшибкаКонтракта("Служебный каталог содержит неизвестный объект")

    состояние: dict[str, Any] | None = None
    if "состояние.json" in фактические_служебные:
        состояние = прочитать_состояние_установки(
            путь_состояния,
            квитанция,
            "журнал установки",
        )
    if состояние is None:
        if фактические_служебные:
            raise ОшибкаКонтракта(
                "Служебные остатки без доказанного журнала сохранены"
            )
        класс_цели, _снимок = классифицировать_фактическую_цель(
            корень,
            цель,
            квитанция,
        )
        допустимые_классы = (
            {"прежняя", "новая"}
            if квитанция["была_цель"]
            else {"отсутствует", "новая"}
        )
        if класс_цели not in допустимые_классы:
            raise ОшибкаКонтракта("Пустой служебный каталог не доказывает цель")
        удалить_служебные_метаданные(
            корень,
            пространство,
            служебный,
            квитанция,
            свидетельство_квитанции,
            удалить_пустое_пространство=(класс_цели == "отсутствует"),
        )
        return

    класс_цели, _снимок_цели = классифицировать_фактическую_цель(
        корень,
        цель,
        квитанция,
    )
    снимок_нового = снять_служебный_снимок_если_есть(
        корень,
        новое,
        допустимые_режимы_корня=frozenset({0o700, 0o755}),
    )
    снимок_прежнего = снять_служебный_снимок_если_есть(корень, прежнее)
    снимок_удаляемого = снять_служебный_снимок_если_есть(корень, удаляемое)
    if снимок_нового is not None:
        проверить_подмножество_снимка(
            снимок_нового,
            квитанция["новый_снимок"],
            "временное новое поколение",
        )
    прежний_эталон = квитанция["прежний_снимок"]
    if прежний_эталон is None:
        if снимок_прежнего is not None or снимок_удаляемого is not None:
            raise ОшибкаКонтракта("Первичная установка содержит чужой резерв")
    else:
        if снимок_прежнего is not None:
            проверить_подмножество_снимка(
                снимок_прежнего,
                прежний_эталон,
                "резерв прежнего поколения",
                полный=(класс_цели != "прежняя"),
            )
        if снимок_удаляемого is not None:
            проверить_подмножество_снимка(
                снимок_удаляемого,
                прежний_эталон,
                "удаляемый резерв",
            )

    фаза = состояние["фаза"]
    if фаза == "принято":
        if класс_цели != "новая" or снимок_нового is not None:
            raise ОшибкаКонтракта("Принятое поколение не совпадает с квитанцией")
        if снимок_прежнего is not None and снимок_удаляемого is not None:
            raise ОшибкаКонтракта("Принятая установка дублирует резерв")
        if снимок_прежнего is not None:
            try:
                удаляемое.lstat()
            except FileNotFoundError:
                pass
            else:
                raise ОшибкаКонтракта("Назначение удаления резерва уже существует")
            потребовать_точный_снимок(
                корень,
                прежнее,
                прежний_эталон,
                "Резерв принятой установки",
            )
            проверить_неизменность_квитанции(
                корень,
                квитанция,
                свидетельство_квитанции,
            )
            переименовать_устойчиво_без_замены(прежнее, удаляемое)
            снимок_удаляемого = снимок_прежнего
        if снимок_удаляемого is not None:
            assert прежний_эталон is not None
            проверить_неизменность_квитанции(
                корень,
                квитанция,
                свидетельство_квитанции,
            )
            удалить_проверенное_подмножество(
                корень,
                удаляемое,
                прежний_эталон,
                "удаляемый резерв",
            )
            синхронизировать_каталог(служебный)
        удалить_служебные_метаданные(
            корень,
            пространство,
            служебный,
            квитанция,
            свидетельство_квитанции,
            удалить_пустое_пространство=False,
        )
        return

    if снимок_удаляемого is not None:
        raise ОшибкаКонтракта("До принятия появился недопустимый удаляемый резерв")
    if прежний_эталон is not None:
        допустимая_форма = (
            класс_цели == "прежняя"
            or (класс_цели == "отсутствует" and снимок_прежнего is not None)
            or (
                класс_цели == "новая"
                and снимок_прежнего is not None
            )
        )
    else:
        допустимая_форма = класс_цели in {"отсутствует", "новая"}
    if not допустимая_форма:
        raise ОшибкаКонтракта("Положение поколений не допускает доказанный откат")
    if фаза != "откачено" or not путь_состояния.exists():
        предыдущее_состояние = dict(состояние)
        состояние = dict(состояние)
        состояние["фаза"] = "откачено"
        записать_состояние_установки(
            служебный,
            состояние,
            предыдущее_состояние,
        )
    if класс_цели == "прежняя" and снимок_прежнего is not None:
        сведения_цели = цель.lstat()
        сведения_резерва = прежнее.lstat()
        if (
            сведения_цели.st_dev == сведения_резерва.st_dev
            and сведения_цели.st_ino == сведения_резерва.st_ino
        ):
            raise ОшибкаКонтракта(
                "Публичное и резервное прежние поколения имеют общий inode"
            )
        проверить_неизменность_квитанции(
            корень,
            квитанция,
            свидетельство_квитанции,
        )
        удалить_проверенное_подмножество(
            корень,
            прежнее,
            снимок_прежнего,
            "дублирующий резерв прежнего поколения",
        )
        синхронизировать_каталог(служебный)
        снимок_прежнего = None
    if класс_цели == "новая" and снимок_нового is not None:
        сведения_цели = цель.lstat()
        сведения_временного = новое.lstat()
        if (
            сведения_цели.st_dev == сведения_временного.st_dev
            and сведения_цели.st_ino == сведения_временного.st_ino
        ):
            raise ОшибкаКонтракта(
                "Публичное и временное новые поколения имеют общий inode"
            )
        проверить_неизменность_квитанции(
            корень,
            квитанция,
            свидетельство_квитанции,
        )
        удалить_проверенное_подмножество(
            корень,
            новое,
            снимок_нового,
            "дублирующее временное новое поколение",
            допустимые_режимы_корня=frozenset({0o700, 0o755}),
        )
        синхронизировать_каталог(служебный)
        снимок_нового = None
    if класс_цели == "новая":
        try:
            новое.lstat()
        except FileNotFoundError:
            pass
        else:
            raise ОшибкаКонтракта("Назначение отката нового поколения занято")
        потребовать_точный_снимок(
            корень,
            цель,
            квитанция["новый_снимок"],
            "Текущее новое поколение отката",
        )
        проверить_неизменность_квитанции(
            корень,
            квитанция,
            свидетельство_квитанции,
        )
        переименовать_устойчиво_без_замены(цель, новое)
        снимок_нового = квитанция["новый_снимок"]
        класс_цели = "отсутствует"
    if прежний_эталон is not None and класс_цели == "отсутствует":
        if снимок_прежнего is None:
            raise ОшибкаКонтракта("Откат потерял доказанный резерв прежней цели")
        потребовать_точный_снимок(
            корень,
            прежнее,
            прежний_эталон,
            "Резерв прежнего поколения отката",
        )
        потребовать_отсутствие_пути(цель, "Цель восстановления прежнего поколения")
        проверить_неизменность_квитанции(
            корень,
            квитанция,
            свидетельство_квитанции,
        )
        переименовать_устойчиво_без_замены(прежнее, цель)
        снимок_прежнего = None
        класс_цели = "прежняя"
    if снимок_нового is not None:
        проверить_неизменность_квитанции(
            корень,
            квитанция,
            свидетельство_квитанции,
        )
        удалить_проверенное_подмножество(
            корень,
            новое,
            квитанция["новый_снимок"],
            "откатываемое новое поколение",
            допустимые_режимы_корня=frozenset({0o700, 0o755}),
        )
        синхронизировать_каталог(служебный)
    удалить_служебные_метаданные(
        корень,
        пространство,
        служебный,
        квитанция,
        свидетельство_квитанции,
        удалить_пустое_пространство=(прежний_эталон is None),
    )


def записать_временное_поколение(
    корень: Path,
    служебный: Path,
    план: Mapping[str, Any],
    выходы: Mapping[str, bytes],
    манифест: Mapping[str, Any],
    транзакция: str,
    после_записи_файла: Callable[[], None] | None = None,
) -> Path:
    проверить_хэш(транзакция, "транзакция временного поколения")
    новое = служебный / "новое"
    создать_каталог_точного_режима(новое, 0o700)
    частичные = служебный / имя_каталога_частичной_записи(
        транзакция
    )
    создать_каталог_точного_режима(частичные, 0o700)
    режимы = {
        запись["целевой_путь"]: запись["режим"]
        for запись in план["записи"]
    }
    созданные_каталоги: set[Path] = {новое}
    for полный_путь in sorted(выходы, key=lambda путь: путь.encode("utf-8")):
        относительный = PurePosixPath(полный_путь).relative_to(
            PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
        )
        цель = новое.joinpath(*относительный.parts)
        недостающие: list[Path] = []
        родитель = цель.parent
        while родитель != новое and not родитель.exists():
            недостающие.append(родитель)
            родитель = родитель.parent
        for каталог in reversed(недостающие):
            создать_каталог_точного_режима(каталог, 0o755)
            созданные_каталоги.add(каталог)
        относительное_имя = относительный.as_posix()
        временный = частичные / (
            hashlib.sha256(относительное_имя.encode("utf-8")).hexdigest() + ".tmp"
        )
        записать_обычный_файл(
            временный,
            выходы[полный_путь],
            режимы[полный_путь],
        )
        потребовать_отсутствие_пути(цель, "Цель полностью записанного файла")
        атомарно_переименовать_без_замены(временный, цель)
        синхронизировать_каталог(частичные)
        синхронизировать_каталог(цель.parent)
        if после_записи_файла is not None:
            после_записи_файла()
    относительный_манифест = PurePosixPath(ПУТЬ_МАНИФЕСТА).name
    временный_манифест = частичные / (
        hashlib.sha256(относительный_манифест.encode("utf-8")).hexdigest() + ".tmp"
    )
    записать_обычный_файл(
        временный_манифест,
        канонические_байты(манифест),
        "100644",
    )
    путь_манифеста = новое / относительный_манифест
    потребовать_отсутствие_пути(путь_манифеста, "Цель манифеста")
    атомарно_переименовать_без_замены(
        временный_манифест,
        путь_манифеста,
    )
    синхронизировать_каталог(частичные)
    синхронизировать_каталог(новое)
    частичные.rmdir()
    синхронизировать_каталог(служебный)
    for каталог in sorted(
        созданные_каталоги,
        key=lambda путь: len(путь.parts),
        reverse=True,
    ):
        каталог.chmod(0o755)
        синхронизировать_каталог(каталог)
    синхронизировать_каталог(служебный)
    return новое


def проверить_неизменность_каталога(
    путь: Path,
    исходные_сведения: os.stat_result,
) -> None:
    текущие = путь.lstat()
    if (
        stat.S_ISLNK(текущие.st_mode)
        or not stat.S_ISDIR(текущие.st_mode)
        or текущие.st_dev != исходные_сведения.st_dev
        or текущие.st_ino != исходные_сведения.st_ino
        or текущие.st_mode != исходные_сведения.st_mode
    ):
        raise ОшибкаКонтракта(
            f"Каталог установки подменён во время операции: {путь}"
        )


def применить_поколение(
    корень_репозитория: Path | str,
    политика: Mapping[str, Any],
    преобразователь: Callable[[Sequence[str]], Sequence[str]],
    *,
    инъекция_сбоя: Callable[[str], None] | None = None,
) -> dict[str, Any]:
    корень = Path(корень_репозитория).resolve()
    if str(
        выполнить_команду_контроля_версий(
            корень,
            "rev-parse",
            "--show-toplevel",
        )
    ).strip() != str(корень):
        raise ОшибкаКонтракта("Корень репозитория не совпадает с Git toplevel")
    проверенная_политика = проверить_политику(политика)
    пространство = корень / ПРОИЗВОДНОЕ_ПРОСТРАНСТВО
    служебный = корень / PurePosixPath(СЛУЖЕБНЫЙ_КАТАЛОГ)
    цель = корень / PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
    восстановить_незавершённую_установку(корень, проверенная_политика)

    прежний_манифест: dict[str, Any] | None = None
    прежний_снимок: dict[str, Any] | None = None
    граница_конфликтной_проекции: dict[str, Any] | None = None
    конфликтные_пути = конфликтные_пути_проекции(корень)
    if конфликтные_пути:
        граница_до = снимок_границы_конфликтной_проекции(корень)
        прежний_снимок = снимок_конфликтного_поколения(
            корень,
            проверенная_политика,
        )
        граница_после = снимок_границы_конфликтной_проекции(корень)
        if канонические_байты(граница_до) != канонические_байты(
            граница_после
        ):
            raise ОшибкаКонтракта(
                "Граница конфликтной проекции изменилась во время чтения"
            )
        граница_конфликтной_проекции = граница_после
        if прежний_снимок is None:
            raise ОшибкаКонтракта(
                "Конфликтное поколение не имеет материального "
                "доверенного снимка"
            )
    elif пространство.exists():
        прежний_манифест = проверить_производное_пространство(
            корень,
            проверенная_политика,
        )
        assert прежний_манифест is not None
        _манифест, прежний_снимок = проверить_дерево_по_манифесту(
            корень,
            цель,
            проверенная_политика,
            прежний_манифест,
        )

    разрешить_конфликтную_цель = (
        bool(конфликтные_пути)
        and прежний_манифест is None
        and прежний_снимок is not None
    )
    план = построить_план(
        корень,
        проверенная_политика,
        преобразователь,
        разрешить_конфликтную_цель=разрешить_конфликтную_цель,
    )
    выходы = сформировать_выходы(корень, план, преобразователь)
    манифест = сформировать_манифест(план, выходы)
    контрольный_план = построить_план(
        корень,
        проверенная_политика,
        преобразователь,
        разрешить_конфликтную_цель=разрешить_конфликтную_цель,
    )
    if контрольный_план["хэш_плана"] != план["хэш_плана"]:
        raise ОшибкаКонтракта(
            "Исходный снимок изменился во время формирования поколения"
        )
    if прежний_манифест is not None and канонические_байты(
        прежний_манифест
    ) == канонические_байты(манифест):
        проверка = проверить_манифест(
            корень,
            проверенная_политика,
            манифест,
            цель,
            преобразователь,
            разрешить_конфликтные_стадии_проекции=False,
        )
        return {
            "состояние": "без_изменений",
            "исходных_файлов": len(план["записи"]),
            "целевых_файлов": len(выходы),
            "хэш_плана": план["хэш_плана"],
            "проверка": проверка["состояние"],
        }

    была_цель = прежний_снимок is not None
    устойчивый_прежний_снимок = (
        устойчивый_снимок_дерева(прежний_снимок)
        if прежний_снимок is not None
        else None
    )
    ожидаемый_новый_снимок = сформировать_ожидаемый_снимок_поколения(
        план,
        выходы,
        манифест,
    )
    прежний_хэш = (
        хэш_дерева(устойчивый_прежний_снимок)
        if устойчивый_прежний_снимок is not None
        else None
    )
    новый_хэш = хэш_дерева(ожидаемый_новый_снимок)
    квитанция = {
        "схема": СХЕМА_КВИТАНЦИИ_УСТАНОВКИ,
        "транзакция": f"sha256:{secrets.token_hex(32)}",
        "целевая_область": ЦЕЛЕВАЯ_ОБЛАСТЬ,
        "служебный_каталог": СЛУЖЕБНЫЙ_КАТАЛОГ,
        "была_цель": была_цель,
        "новый_снимок": ожидаемый_новый_снимок,
        "хэш_нового_дерева": новый_хэш,
        "прежний_снимок": устойчивый_прежний_снимок,
        "хэш_прежнего_дерева": прежний_хэш,
    }
    состояние: dict[str, Any] = {
        "схема": СХЕМА_УСТАНОВКИ,
        "транзакция": квитанция["транзакция"],
        "фаза": "строится",
        "была_цель": была_цель,
        "хэш_нового_дерева": новый_хэш,
        "хэш_прежнего_дерева": прежний_хэш,
    }
    записать_квитанцию_установки(корень, квитанция)
    прочитанная_квитанция = прочитать_квитанцию_установки(корень)
    if прочитанная_квитанция is None:
        raise ОшибкаКонтракта("Записанная квитанция установки исчезла")
    (
        _путь_квитанции,
        проверенная_квитанция,
        свидетельство_квитанции,
    ) = прочитанная_квитанция
    if канонические_байты(проверенная_квитанция) != канонические_байты(квитанция):
        raise ОшибкаКонтракта("Записанная квитанция не совпала с транзакцией")
    try:
        if not пространство.exists():
            создать_каталог_точного_режима(пространство, 0o755)
        проверить_точное_имя_дочернего_пути(
            корень,
            ПРОИЗВОДНОЕ_ПРОСТРАНСТВО,
            "производного пространства перед установкой",
        )
        сведения_пространства = пространство.lstat()
        if (
            stat.S_ISLNK(сведения_пространства.st_mode)
            or not stat.S_ISDIR(сведения_пространства.st_mode)
            or stat.S_IMODE(сведения_пространства.st_mode) != 0o755
        ):
            raise ОшибкаКонтракта(
                "Производное пространство подменено до установки"
            )
        создать_каталог_точного_режима(служебный, 0o700)
        сведения_служебного = служебный.lstat()
        записать_состояние_установки(служебный, состояние, None)
    except Exception:
        восстановить_незавершённую_установку(
            корень,
            проверенная_политика,
        )
        raise

    def вызвать_инъекцию(граница: str) -> None:
        if инъекция_сбоя is not None:
            инъекция_сбоя(граница)

    try:
        новое = записать_временное_поколение(
            корень,
            служебный,
            план,
            выходы,
            манифест,
            str(квитанция["транзакция"]),
            lambda: вызвать_инъекцию(
                "после_записи_файла_временного_поколения"
            ),
        )
        _временный_манифест, новый_снимок = проверить_дерево_по_манифесту(
            корень,
            новое,
            проверенная_политика,
            манифест,
        )
        if канонические_байты(
            устойчивый_снимок_дерева(новый_снимок)
        ) != канонические_байты(ожидаемый_новый_снимок):
            raise ОшибкаКонтракта(
                "Построенное поколение не совпадает с внешней квитанцией"
            )
        предыдущее_состояние = dict(состояние)
        состояние["фаза"] = "подготовлено"
        записать_состояние_установки(
            служебный,
            состояние,
            предыдущее_состояние,
        )
        вызвать_инъекцию("после_проверки_временного_поколения")

        финальный_план = построить_план(
            корень,
            проверенная_политика,
            преобразователь,
            разрешить_управляемую_цель=True,
            разрешить_конфликтную_цель=разрешить_конфликтную_цель,
            разрешить_квитанцию_установки=True,
        )
        if финальный_план["хэш_плана"] != план["хэш_плана"]:
            raise ОшибкаКонтракта(
                "Исходный снимок изменился перед установкой поколения"
            )
        вызвать_инъекцию("перед_установкой")
        проверить_неизменность_квитанции(
            корень,
            квитанция,
            свидетельство_квитанции,
        )
        if граница_конфликтной_проекции is not None:
            текущий_конфликтный_снимок = снимок_целевого_дерева(корень, цель)
            if (
                текущий_конфликтный_снимок != прежний_снимок
                or канонические_байты(
                    снимок_границы_конфликтной_проекции(корень)
                )
                != канонические_байты(
                    граница_конфликтной_проекции
                )
            ):
                raise ОшибкаКонтракта(
                    "Конфликтная проекция изменилась перед установкой"
                )
        проверить_неизменность_каталога(
            пространство,
            сведения_пространства,
        )
        проверить_неизменность_каталога(служебный, сведения_служебного)
        прежнее = служебный / "прежнее"
        if была_цель:
            if снимок_целевого_дерева(корень, цель) != прежний_снимок:
                raise ОшибкаКонтракта(
                    "Целевое поколение изменилось перед резервированием"
                )
            потребовать_отсутствие_пути(прежнее, "Резерв прежнего поколения")
            проверить_неизменность_квитанции(
                корень,
                квитанция,
                свидетельство_квитанции,
            )
            переименовать_устойчиво_без_замены(цель, прежнее)
            предыдущее_состояние = dict(состояние)
            состояние["фаза"] = "прежнее_зарезервировано"
            записать_состояние_установки(
                служебный,
                состояние,
                предыдущее_состояние,
            )
            вызвать_инъекцию("после_резервирования_старого")
            проверить_неизменность_каталога(
                пространство,
                сведения_пространства,
            )
            проверить_неизменность_каталога(служебный, сведения_служебного)
        потребовать_точный_снимок(
            корень,
            новое,
            ожидаемый_новый_снимок,
            "Подготовленное новое поколение",
        )
        потребовать_отсутствие_пути(цель, "Целевая область перед установкой")
        проверить_неизменность_квитанции(
            корень,
            квитанция,
            свидетельство_квитанции,
        )
        переименовать_устойчиво_без_замены(новое, цель)
        предыдущее_состояние = dict(состояние)
        состояние["фаза"] = "новое_установлено"
        записать_состояние_установки(
            служебный,
            состояние,
            предыдущее_состояние,
        )
        вызвать_инъекцию("после_установки_нового")
        проверить_неизменность_каталога(
            пространство,
            сведения_пространства,
        )
        проверить_неизменность_каталога(служебный, сведения_служебного)
        проверка = проверить_манифест(
            корень,
            проверенная_политика,
            манифест,
            цель,
            преобразователь,
            разрешить_служебную_область=True,
            разрешить_конфликтные_стадии_проекции=разрешить_конфликтную_цель,
        )
        вызвать_инъекцию("после_проверки_установленного_поколения")
        if (
            граница_конфликтной_проекции is not None
            and канонические_байты(
                снимок_границы_конфликтной_проекции(корень)
            )
            != канонические_байты(
                граница_конфликтной_проекции
            )
        ):
            raise ОшибкаКонтракта(
                "Граница конфликтной проекции изменилась до принятия"
            )
        предыдущее_состояние = dict(состояние)
        состояние["фаза"] = "принято"
        записать_состояние_установки(
            служебный,
            состояние,
            предыдущее_состояние,
        )
        вызвать_инъекцию("после_принятия")
        восстановить_незавершённую_установку(
            корень,
            проверенная_политика,
        )
    except Exception:
        восстановить_незавершённую_установку(
            корень,
            проверенная_политика,
        )
        raise
    return {
        "состояние": "установлено",
        "исходных_файлов": len(план["записи"]),
        "целевых_файлов": len(выходы),
        "хэш_плана": план["хэш_плана"],
        "проверка": проверка["состояние"],
    }


def вычислить_ожидаемые_байты_цели(
    корень: Path,
    запись: Mapping[str, Any],
    преобразователь_содержимого: Callable[[Mapping[str, Any], bytes], bytes] | None,
) -> bytes:
    исходные_байты = безопасно_прочитать_обычный_файл(
        корень,
        запись["исходный_путь"],
    )
    if хэш_байтов(исходные_байты) != запись["хэш_источника"]:
        raise ОшибкаКонтракта(
            "Исходные байты не совпадают с хэшем записи перед повторным "
            f"преобразованием: {запись['исходный_путь']}"
        )
    if запись["действие_содержимого"] == "сохранить_байты":
        return исходные_байты
    if преобразователь_содержимого is None:
        raise ОшибкаКонтракта(
            "Структурный выход требует независимого повторного преобразования "
            "автоматизацией FUM-STEP-0129"
        )
    ожидаемые_байты = преобразователь_содержимого(запись, исходные_байты)
    if not isinstance(ожидаемые_байты, bytes):
        raise ОшибкаКонтракта(
            "Преобразователь содержимого обязан вернуть точные байты"
        )
    return ожидаемые_байты


def проверить_манифест(
    корень_репозитория: Path | str,
    политика: Mapping[str, Any],
    манифест: Mapping[str, Any],
    корень_цели: Path | str,
    преобразователь: Callable[[Sequence[str]], Sequence[str]],
    преобразователь_содержимого: Callable[[Mapping[str, Any], bytes], bytes]
    | None = None,
    разрешить_служебную_область: bool = False,
    разрешить_конфликтные_стадии_проекции: bool = False,
) -> dict[str, Any]:
    заданный_корень = Path(корень_репозитория).absolute()
    корень = заданный_корень.resolve()
    проверенная_политика = проверить_политику(политика)
    if not разрешить_конфликтные_стадии_проекции:
        проверить_отсутствие_конфликтных_стадий_проекции(корень)
    if not isinstance(манифест, Mapping):
        raise ОшибкаКонтракта("Манифест обязан быть JSON-объектом")
    потребовать_поля(манифест, ПОЛЯ_МАНИФЕСТА, "манифест")
    if манифест["схема"] != СХЕМА_МАНИФЕСТА:
        raise ОшибкаКонтракта("Неподдержанная схема манифеста")
    проверить_хэш(манифест["хэш_плана"], "манифест.хэш_плана")
    if манифест["хэш_политики"] != хэш_значения(проверенная_политика):
        raise ОшибкаКонтракта("Манифест устарел: хэш политики изменился")
    проверить_манифест_владения(проверенная_политика, манифест)

    свежий_план = построить_план(
        корень,
        проверенная_политика,
        преобразователь,
        разрешить_управляемую_цель=разрешить_служебную_область,
        разрешить_квитанцию_установки=разрешить_служебную_область,
    )
    if манифест["хэш_плана"] != свежий_план["хэш_плана"]:
        raise ОшибкаКонтракта("Манифест устарел: хэш сухого плана изменился")
    for поле in (
        "исходный_снимок",
        "исходная_область",
        "производное_пространство",
        "целевая_область",
        "корень_файлов",
        "путь_манифеста",
        "исключённые_префиксы",
        "преобразование",
        "форматная_политика",
        "пустые_каталоги",
    ):
        if канонические_байты(манифест[поле]) != канонические_байты(
            свежий_план[поле]
        ):
            raise ОшибкаКонтракта(f"Манифест устарел: изменилось поле {поле}")

    ожидаемые_записи = {
        запись["исходный_путь"]: запись for запись in свежий_план["записи"]
    }
    ожидаемые_выходы: dict[str, bytes] = (
        сформировать_выходы(корень, свежий_план, преобразователь)
        if преобразователь_содержимого is None
        else {}
    )
    фактические_записи = манифест["записи"]
    if not isinstance(фактические_записи, list):
        raise ОшибкаКонтракта("Манифест не содержит массив записей")
    по_источникам: dict[str, Mapping[str, Any]] = {}
    по_целям: dict[str, Mapping[str, Any]] = {}
    for запись in фактические_записи:
        if not isinstance(запись, Mapping):
            raise ОшибкаКонтракта("Манифест содержит не-объект вместо записи")
        потребовать_поля(
            запись,
            ПОЛЯ_ЗАПИСИ_МАНИФЕСТА,
            "запись манифеста",
        )
        источник = запись["исходный_путь"]
        цель = запись["целевой_путь"]
        if not isinstance(источник, str) or not isinstance(цель, str):
            raise ОшибкаКонтракта("Пути записи манифеста обязаны быть строками")
        if источник in по_источникам or цель in по_целям:
            raise ОшибкаКонтракта("Манифест повторяет исходный или целевой путь")
        проверить_хэш(запись["хэш_цели"], f"хэш цели {цель}")
        if (
            запись["действие_содержимого"] == "сохранить_байты"
            and запись["хэш_цели"] != запись["хэш_источника"]
        ):
            raise ОшибкаКонтракта(
                f"Побайтовый выход не совпадает с источником: {источник}"
            )
        по_источникам[источник] = запись
        по_целям[цель] = запись
    if set(по_источникам) != set(ожидаемые_записи):
        raise ОшибкаКонтракта(
            "Манифест устарел: состав исходного инвентаря изменился"
        )
    for источник, ожидаемая in ожидаемые_записи.items():
        фактическая = по_источникам[источник]
        for поле in ПОЛЯ_ЗАПИСИ_МАНИФЕСТА - {"хэш_цели"}:
            if фактическая[поле] != ожидаемая[поле]:
                raise ОшибкаКонтракта(
                    f"Манифест устарел: изменилось поле {поле} источника {источник}"
                )
        ожидаемые_байты = (
            ожидаемые_выходы[ожидаемая["целевой_путь"]]
            if преобразователь_содержимого is None
            else вычислить_ожидаемые_байты_цели(
                корень,
                ожидаемая,
                преобразователь_содержимого,
            )
        )
        ожидаемые_выходы[ожидаемая["целевой_путь"]] = ожидаемые_байты
        if фактическая["хэш_цели"] != хэш_байтов(ожидаемые_байты):
            raise ОшибкаКонтракта(
                "Хэш структурного выхода не совпадает с независимым повторным "
                f"преобразованием: {источник}"
            )
    ожидаемый_манифест = сформировать_манифест(
        свежий_план,
        ожидаемые_выходы,
    )
    if канонические_байты(манифест) != канонические_байты(
        ожидаемый_манифест
    ):
        raise ОшибкаКонтракта(
            "Манифест не совпадает с независимо сформированным каноническим объектом"
        )

    ожидаемый_корень_цели = Path(
        os.path.abspath(заданный_корень / PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ))
    )
    if Path(os.path.abspath(корень_цели)) != ожидаемый_корень_цели:
        raise ОшибкаКонтракта(
            "Корень цели не совпадает с закреплённой целевой областью"
        )
    целевой_снимок = снимок_целевого_дерева(корень)
    итоговые_файлы = манифест["итоговые_файлы"]
    if not isinstance(итоговые_файлы, list) or not all(
        isinstance(путь, str) for путь in итоговые_файлы
    ):
        raise ОшибкаКонтракта("Манифест содержит некорректный итоговый набор файлов")
    ожидаемый_управляемый_набор = sorted(
        [*свежий_план["итоговые_целевые_пути"], ПУТЬ_МАНИФЕСТА],
        key=lambda путь: путь.encode("utf-8"),
    )
    if итоговые_файлы != ожидаемый_управляемый_набор:
        raise ОшибкаКонтракта(
            "Итоговый управляемый набор не совпадает с планом и путём манифеста"
        )
    ожидаемые_относительные = {
        PurePosixPath(путь).relative_to(PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)).as_posix()
        for путь in итоговые_файлы
    }
    фактические_относительные = set(целевой_снимок["файлы"])
    отсутствуют = sorted(ожидаемые_относительные - фактические_относительные)
    лишние = sorted(фактические_относительные - ожидаемые_относительные)
    if отсутствуют:
        raise ОшибкаКонтракта(f"В целевой области отсутствуют файлы: {отсутствуют}")
    if лишние:
        raise ОшибкаКонтракта(f"В целевой области обнаружены лишние файлы: {лишние}")
    ожидаемые_каталоги: set[str] = set()
    for относительный in ожидаемые_относительные:
        части = PurePosixPath(относительный).parts
        for глубина in range(1, len(части)):
            ожидаемые_каталоги.add("/".join(части[:глубина]))
    if set(целевой_снимок["каталоги"]) != ожидаемые_каталоги:
        raise ОшибкаКонтракта(
            "Набор целевых каталогов содержит отсутствующий или лишний каталог"
        )

    относительный_манифест = PurePosixPath(ПУТЬ_МАНИФЕСТА).relative_to(
        PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
    ).as_posix()
    запись_манифеста = целевой_снимок["файлы"][относительный_манифест]
    if запись_манифеста["байты"] != канонические_байты(манифест):
        raise ОшибкаКонтракта(
            "Байты манифеста не совпадают с каноническим проверяемым объектом"
        )
    if запись_манифеста["режим"] != "100644":
        raise ОшибкаКонтракта("Манифест не должен быть исполняемым")

    for полный_путь, запись in по_целям.items():
        относительный = PurePosixPath(полный_путь).relative_to(
            PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ)
        ).as_posix()
        целевая_запись = целевой_снимок["файлы"][относительный]
        if целевая_запись["хэш"] != запись["хэш_цели"]:
            raise ОшибкаКонтракта(
                f"хэш целевого файла не совпадает: {полный_путь}"
            )
        if целевая_запись["режим"] != запись["режим"]:
            raise ОшибкаКонтракта(
                f"Режим целевого файла не совпадает: {полный_путь}"
            )
    контрольный_план = построить_план(
        корень,
        проверенная_политика,
        преобразователь,
        разрешить_управляемую_цель=разрешить_служебную_область,
        разрешить_квитанцию_установки=разрешить_служебную_область,
    )
    if контрольный_план["хэш_плана"] != свежий_план["хэш_плана"]:
        raise ОшибкаКонтракта(
            "Исходный снимок изменился во время проверки целевого поколения"
        )
    if not разрешить_конфликтные_стадии_проекции:
        проверить_отсутствие_конфликтных_стадий_проекции(корень)
    if снимок_целевого_дерева(корень) != целевой_снимок:
        raise ОшибкаКонтракта(
            "Целевое поколение изменилось во время проверки"
        )
    return {
        "состояние": "действителен",
        "исходных_файлов": len(ожидаемые_записи),
        "целевых_файлов": len(по_целям),
        "управляемых_файлов": len(итоговые_файлы),
        "исходный_снимок": свежий_план["исходный_снимок"],
        "хэш_плана": свежий_план["хэш_плана"],
    }


def преобразователь_процесса(
    команда: Sequence[str],
    проверка_границы: Callable[[], None] | None = None,
) -> Callable[[Sequence[str]], Sequence[str]]:
    if not команда:
        raise ОшибкаКонтракта("Команда преобразователя пуста")

    def преобразовать(строки: Sequence[str]) -> Sequence[str]:
        if проверка_границы is not None:
            проверка_границы()
        try:
            try:
                результат = subprocess.run(
                    list(команда),
                    input=json.dumps(list(строки), ensure_ascii=False) + "\n",
                    text=True,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    check=True,
                )
            finally:
                if проверка_границы is not None:
                    проверка_границы()
        except (OSError, subprocess.CalledProcessError) as ошибка:
            пояснение = getattr(ошибка, "stderr", None) or str(ошибка)
            raise ОшибкаКонтракта(
                f"Не удалось вызвать LinguisticKit: {str(пояснение).strip()}"
            ) from ошибка
        try:
            ответ = json.loads(
                результат.stdout,
                parse_constant=отклонить_нестандартное_число,
            )
        except json.JSONDecodeError as ошибка:
            raise ОшибкаКонтракта(
                "LinguisticKit вернул некорректный JSON"
            ) from ошибка
        if not isinstance(ответ, list) or not all(
            isinstance(строка, str) for строка in ответ
        ):
            raise ОшибкаКонтракта(
                "LinguisticKit обязан вернуть JSON-массив строк"
            )
        return ответ

    return преобразовать


def прочитать_закреплённое_дерево_зависимости(
    зависимость: Path,
) -> dict[str, dict[str, str]]:
    сырые_данные = выполнить_команду_контроля_версий(
        зависимость,
        "ls-tree",
        "-rz",
        "--full-tree",
        РЕВИЗИЯ_ЗАВИСИМОСТИ,
        двоичный=True,
    )
    assert isinstance(сырые_данные, bytes)
    дерево: dict[str, dict[str, str]] = {}
    for сырой_элемент in сырые_данные.split(b"\0"):
        if not сырой_элемент:
            continue
        try:
            заголовок, сырой_путь = сырой_элемент.split(b"\t", 1)
            режим, тип, идентификатор = заголовок.decode("ascii").split(" ", 2)
            путь = сырой_путь.decode("utf-8")
        except (ValueError, UnicodeError) as ошибка:
            raise ОшибкаКонтракта(
                "Закреплённое дерево LinguisticKit имеет некорректную Git-запись"
            ) from ошибка
        проверить_относительный_путь(путь, "путь закреплённой зависимости")
        if тип != "blob" or режим not in {"100644", "100755"}:
            raise ОшибкаКонтракта(
                "Закреплённое дерево LinguisticKit содержит неподдержанный объект: "
                f"{путь} ({режим} {тип})"
            )
        if путь in дерево or re.fullmatch(r"[0-9a-f]{40}", идентификатор) is None:
            raise ОшибкаКонтракта(
                f"Закреплённое дерево LinguisticKit неоднозначно: {путь}"
            )
        дерево[путь] = {
            "режим": режим,
            "идентификатор": идентификатор,
        }
    if not дерево:
        raise ОшибкаКонтракта("Закреплённое дерево LinguisticKit пусто")
    return дерево


def собрать_фактические_файлы_зависимости(
    зависимость: Path,
    ожидаемые_пути: set[str],
) -> set[str]:
    файлы_зависимости: set[str] = set()

    def отказ_обхода(ошибка: OSError) -> None:
        raise ОшибкаКонтракта(
            f"Не удалось полностью обследовать LinguisticKit: {ошибка}"
        ) from ошибка

    for текущий_каталог, каталоги, файлы in os.walk(
        зависимость,
        topdown=True,
        followlinks=False,
        onerror=отказ_обхода,
    ):
        текущий = Path(текущий_каталог)
        относительный_каталог = текущий.relative_to(зависимость).as_posix()
        if относительный_каталог == ".":
            относительный_каталог = ""
        допущенные_каталоги: list[str] = []
        for имя in каталоги:
            относительный = (
                f"{относительный_каталог}/{имя}"
                if относительный_каталог
                else имя
            )
            if not относительный_каталог and имя == ".git":
                continue
            if (
                not относительный_каталог
                and имя in {".build", ".swiftpm"}
                and not any(
                    путь == имя or путь.startswith(f"{имя}/")
                    for путь in ожидаемые_пути
                )
            ):
                raise ОшибкаКонтракта(
                    "Материализованный LinguisticKit содержит локальное состояние "
                    f"сборки: {относительный}"
                )
            сведения = получить_сведения_без_перехода(
                текущий / имя,
                "материализованной зависимости",
            )
            if stat.S_ISLNK(сведения.st_mode) or not stat.S_ISDIR(сведения.st_mode):
                raise ОшибкаКонтракта(
                    "Материализованный LinguisticKit содержит небезопасный объект: "
                    f"{относительный}"
                )
            допущенные_каталоги.append(имя)
        каталоги[:] = допущенные_каталоги
        for имя in файлы:
            относительный = (
                f"{относительный_каталог}/{имя}"
                if относительный_каталог
                else имя
            )
            if относительный == ".git":
                continue
            сведения = получить_сведения_без_перехода(
                текущий / имя,
                "материализованной зависимости",
            )
            if not stat.S_ISREG(сведения.st_mode):
                raise ОшибкаКонтракта(
                    "Материализованный LinguisticKit содержит специальный объект: "
                    f"{относительный}"
                )
            файлы_зависимости.add(относительный)
    return файлы_зависимости


def идентификатор_блоба(данные: bytes) -> str:
    заголовок = f"blob {len(данные)}\0".encode("ascii")
    return hashlib.sha1(заголовок + данные).hexdigest()


def проверить_файлы_по_дереву_зависимости(
    зависимость: Path,
    ожидаемое_дерево: Mapping[str, Mapping[str, str]],
) -> None:
    ожидаемые_пути = set(ожидаемое_дерево)
    фактические_пути = собрать_фактические_файлы_зависимости(
        зависимость,
        ожидаемые_пути,
    )
    if фактические_пути != ожидаемые_пути:
        raise ОшибкаКонтракта(
            "Материализованный LinguisticKit не совпадает с закреплённым деревом; "
            f"отсутствуют={sorted(ожидаемые_пути - фактические_пути)}, "
            f"лишние={sorted(фактические_пути - ожидаемые_пути)}"
        )
    for путь in sorted(ожидаемые_пути, key=lambda значение: значение.encode("utf-8")):
        данные, фактические_сведения = безопасно_прочитать_файл_со_сведениями(
            зависимость,
            путь,
        )
        фактический_режим = (
            "100755" if фактические_сведения.st_mode & 0o111 else "100644"
        )
        ожидаемая_запись = ожидаемое_дерево[путь]
        if фактический_режим != ожидаемая_запись["режим"]:
            raise ОшибкаКонтракта(
                f"Режим файла LinguisticKit не совпадает с закреплённым деревом: {путь}"
            )
        if идентификатор_блоба(данные) != ожидаемая_запись["идентификатор"]:
            raise ОшибкаКонтракта(
                f"Байты файла LinguisticKit не совпадают с закреплённым деревом: {путь}"
            )


def проверить_материализацию_зависимости(корень: Path) -> None:
    зависимость = корень / PurePosixPath(ПУТЬ_ЗАВИСИМОСТИ)
    сведения = проверить_цепочку_без_ссылок(корень, ПУТЬ_ЗАВИСИМОСТИ)
    if not stat.S_ISDIR(сведения.st_mode):
        raise ОшибкаКонтракта(
            "LinguisticKit не материализован как закреплённая Git-зависимость"
        )
    вершина = str(
        выполнить_команду_контроля_версий(зависимость, "rev-parse", "HEAD")
    ).strip()
    if вершина != РЕВИЗИЯ_ЗАВИСИМОСТИ:
        raise ОшибкаКонтракта(
            f"Материализованный LinguisticKit имеет неверную ревизию: {вершина}"
        )
    ожидаемое_дерево = прочитать_закреплённое_дерево_зависимости(зависимость)
    проверить_файлы_по_дереву_зависимости(зависимость, ожидаемое_дерево)


def развернуть_архив_дерева(байты_архива: bytes, цель: Path) -> None:
    замеченные_пути: set[str] = set()
    try:
        with tarfile.open(fileobj=io.BytesIO(байты_архива), mode="r:") as архив:
            for элемент in архив.getmembers():
                путь = PurePosixPath(элемент.name)
                строка_пути = путь.as_posix()
                проверить_относительный_путь(
                    строка_пути,
                    "путь из неизменяемого архива",
                )
                if строка_пути in замеченные_пути:
                    raise ОшибкаКонтракта(
                        f"Неизменяемый архив повторяет путь: {строка_пути}"
                    )
                замеченные_пути.add(строка_пути)
                фактический_путь = цель.joinpath(*путь.parts)
                if элемент.isdir():
                    фактический_путь.mkdir(parents=True, exist_ok=True)
                    continue
                if not элемент.isfile():
                    raise ОшибкаКонтракта(
                        "Неизменяемый архив содержит неподдержанный объект: "
                        f"{строка_пути}"
                    )
                фактический_путь.parent.mkdir(parents=True, exist_ok=True)
                источник = архив.extractfile(элемент)
                if источник is None:
                    raise ОшибкаКонтракта(
                        f"Не удалось прочитать файл неизменяемого архива: {строка_пути}"
                    )
                данные = источник.read()
                if len(данные) != элемент.size:
                    raise ОшибкаКонтракта(
                        f"Файл неизменяемого архива прочитан не полностью: {строка_пути}"
                    )
                фактический_путь.write_bytes(данные)
                фактический_путь.chmod(0o755 if элемент.mode & 0o111 else 0o644)
    except ОшибкаКонтракта:
        raise
    except (OSError, tarfile.TarError) as ошибка:
        raise ОшибкаКонтракта(
            f"Не удалось развернуть неизменяемый Git-архив: {ошибка}"
        ) from ошибка


@contextmanager
def подготовить_изолированный_преобразователь(
    корень: Path,
) -> Iterator[tuple[list[str], Callable[[], None]]]:
    проверить_материализацию_зависимости(корень)
    зависимость = корень / PurePosixPath(ПУТЬ_ЗАВИСИМОСТИ)
    ожидаемое_дерево = прочитать_закреплённое_дерево_зависимости(зависимость)
    вершина_репозитория = str(
        выполнить_команду_контроля_версий(корень, "rev-parse", "HEAD")
    ).strip()
    архив_обёртки = выполнить_команду_контроля_версий(
        корень,
        "archive",
        "--format=tar",
        вершина_репозитория,
        "--",
        "Инструменты/fum-proverka-nazvanij-avtomatizacij",
        двоичный=True,
    )
    архив_зависимости = выполнить_команду_контроля_версий(
        зависимость,
        "archive",
        "--format=tar",
        РЕВИЗИЯ_ЗАВИСИМОСТИ,
        двоичный=True,
    )
    assert isinstance(архив_обёртки, bytes)
    assert isinstance(архив_зависимости, bytes)
    with tempfile.TemporaryDirectory(prefix="fum-preobrazovatelj-") as временный:
        временный_корень = Path(временный)
        развернуть_архив_дерева(архив_обёртки, временный_корень)
        изолированная_зависимость = временный_корень / PurePosixPath(
            ПУТЬ_ЗАВИСИМОСТИ
        )
        изолированная_зависимость.mkdir(parents=True, exist_ok=True)
        развернуть_архив_дерева(архив_зависимости, изолированная_зависимость)
        проверить_файлы_по_дереву_зависимости(
            изолированная_зависимость,
            ожидаемое_дерево,
        )
        пакет = (
            временный_корень
            / "Инструменты"
            / "fum-proverka-nazvanij-avtomatizacij"
        )
        if not (пакет / "Package.swift").is_file():
            raise ОшибкаКонтракта(
                "Неизменяемый снимок не содержит пакет преобразователя названий"
            )

        def проверить_изолированную_границу() -> None:
            текущая_вершина = str(
                выполнить_команду_контроля_версий(корень, "rev-parse", "HEAD")
            ).strip()
            if текущая_вершина != вершина_репозитория:
                raise ОшибкаКонтракта(
                    "Вершина репозитория изменилась после подготовки преобразователя"
                )
            проверить_файлы_по_дереву_зависимости(
                изолированная_зависимость,
                ожидаемое_дерево,
            )

        команда = [
            "swift",
            "run",
            "--quiet",
            "--package-path",
            str(пакет),
            "--scratch-path",
            str(временный_корень / "сборка"),
            "preobrazovatj-nazvaniya",
        ]
        yield команда, проверить_изолированную_границу


def записать_машинные_данные(значение: Any) -> None:
    sys.stdout.buffer.write(канонические_байты(значение))


def построить_анализатор() -> argparse.ArgumentParser:
    анализатор = argparse.ArgumentParser(allow_abbrev=False)
    подкоманды = анализатор.add_subparsers(dest="команда", required=True)
    for имя in (
        "проверить-контракт",
        "план",
        "применить",
        "проверить-манифест",
    ):
        команда = подкоманды.add_parser(имя, allow_abbrev=False)
        команда.add_argument("--корень-репозитория", required=True)
        команда.add_argument("--контракт", required=True)
    подкоманды.choices["проверить-манифест"].add_argument(
        "--манифест",
        required=True,
    )
    return анализатор


def главная(аргументы: Sequence[str] | None = None) -> int:
    разобранные = построить_анализатор().parse_args(аргументы)
    корень = Path(разобранные.корень_репозитория).resolve()
    try:
        политика = загрузить_политику(Path(разобранные.контракт))
        if разобранные.команда == "проверить-контракт":
            записать_машинные_данные(
                {
                    "состояние": "действителен",
                    "схема": политика["схема"],
                    "хэш_политики": хэш_значения(политика),
                    "целевая_область": политика["целевая_область"],
                }
            )
            return 0
        with подготовить_изолированный_преобразователь(
            корень
        ) as (команда, проверка_границы):
            преобразователь = преобразователь_процесса(
                команда,
                проверка_границы,
            )
            if разобранные.команда == "план":
                записать_машинные_данные(
                    построить_план(корень, политика, преобразователь)
                )
                return 0
            if разобранные.команда == "применить":
                записать_машинные_данные(
                    применить_поколение(
                        корень,
                        политика,
                        преобразователь,
                    )
                )
                return 0
            манифест = загрузить_машинные_данные(
                Path(разобранные.манифест),
                "манифест",
            )
            записать_машинные_данные(
                проверить_манифест(
                    корень,
                    политика,
                    манифест,
                    корень / PurePosixPath(ЦЕЛЕВАЯ_ОБЛАСТЬ),
                    преобразователь,
                )
            )
            return 0
    except ОшибкаКонтракта as ошибка:
        print(str(ошибка), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(главная())

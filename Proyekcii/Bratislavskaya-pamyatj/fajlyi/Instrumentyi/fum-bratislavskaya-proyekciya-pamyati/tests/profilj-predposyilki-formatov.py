#!/usr/bin/env python3
"""Измерить конечный сценарный допуск и переход закреплённой компактной фикстуры."""

import argparse
import hashlib
import json
from pathlib import Path
import statistics
import time

from test_переход_форматов_основной_ветки import ПроверкаПереходаФорматов


def измерить(действие, повторов):
    времена = []
    for _ in range(повторов):
        начало = time.perf_counter_ns()
        действие()
        времена.append(time.perf_counter_ns() - начало)
    return {"повторов": повторов, "наносекунды": времена,
            "медиана_наносекунды": int(statistics.median(времена)),
            "сумма_наносекунды": sum(времена)}


def профиль():
    случай = ПроверкаПереходаФорматов()
    случай.подготовить()
    try:
        модуль = случай.модуль
        политика = случай.политика
        корень = случай.фикстура.корень
        данные = случай.установить("поколение-master-v2.json")
        байты = '"use strict"; const имя = значение => значение;\r\n'.encode()

        def проверить_сценарии():
            for путь in модуль.пути_сценариев_ответа:
                assert модуль.классифицировать_содержимое(корень, путь, политика, байты)[1] == "сохранить_байты"

        результаты = {
            "зарегистрированные_сценарии": измерить(проверить_сценарии, 5),
            "владение_полным_прежним_поколением": измерить(
                lambda: модуль.проверить_манифест_владения(политика, данные["манифест"]), 20),
        }
        карта = случай.прочитать("поколение-ведущей-v2.json")["исходники_hex"][".mailmap"]
        случай.фикстура._записать(".mailmap", bytes.fromhex(карта))
        результаты["переход_компактного_поколения"] = измерить(
            lambda: модуль.применить_поколение(корень, политика, случай.преобразователь), 1)
        результаты["независимая_проверка"] = измерить(случай.проверить_текущее, 1)
        снимок = случай.фикстура._снимок_поколения(политика)
        результаты["неизменный_повтор"] = измерить(
            lambda: модуль.применить_поколение(корень, политика, случай.преобразователь), 1)
        assert снимок == случай.фикстура._снимок_поколения(политика)
        база = случай.каталог.parents[1]
        входы = [Path(__file__).resolve(),
                 случай.каталог / "scripts/братиславская_проекция_памяти.py",
                 случай.каталог / "контракт-v2.json",
                 случай.каталог / "совместимость/контракт-v2-до-сценариев-и-карты-авторов.json",
                 случай.каталог / "tests/test_переход_форматов_основной_ветки.py",
                 случай.каталог / "tests/test_братиславская_проекция_памяти.py",
                 база / "Инструменты/fum-perevod-obyyavlenij-koda-na-russkij-yazyik/scripts/разбор_сценария.py",
                 база / "Инструменты/fum-perevod-obyyavlenij-koda-na-russkij-yazyik/scripts/перевести-объявления-кода.py"]
        входы.extend(случай.каталог / "tests/фикстуры" / имя for имя in
                     ("поколение-master-v2.json", "поколение-ведущей-v2.json"))
        return {"измерение": "perf_counter_ns", "область": "компактные фикстуры без Swift",
                "происхождение_поколения": данные["происхождение"],
                "хэш_текущей_политики": модуль.хэш_значения(политика),
                "входы": {путь.relative_to(база).as_posix(): "sha256:" + hashlib.sha256(путь.read_bytes()).hexdigest()
                           for путь in входы}, "результаты": результаты}
    finally:
        случай.doCleanups()


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    параметры = разбор.parse_args()
    результат = профиль()
    параметры.выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(результат["результаты"], ensure_ascii=False))

    def _преобразователь(сам, соответствия=None):
        соответствия = соответствия or {
            "Документация": "Dokumentaciya",
            "Пример": "Primer",
            "Журнал": "Zhurnal",
            "запрос": "zapros",
            "Каталог": "Katalog",
            "файл": "fajl",
        }

        def преобразовать(строки):
            return [соответствия.get(строка, строка) for строка in строки]

        return преобразовать

    def _преобразователь_подстрок(сам, соответствия):
        def преобразовать(строки):
            результаты = []
            for строка in строки:
                результат = строка
                for исходное, целевое in соответствия.items():
                    результат = результат.replace(исходное, целевое)
                результаты.append(результат)
            return результаты

        return преобразовать

    def _добавить_свежесть(сам, содержание, время="2026-01-02 03:04:05 MSK"):
        каноническое = содержание if содержание.endswith("\n") else содержание + "\n"
        хэш = hashlib.sha256(каноническое.encode("utf-8")).hexdigest()
        return (
            каноническое
            + "\n<!-- FUM-MD-RECENCY:BEGIN -->\n"
            + f"<!-- last-content-edit: {время} -->\n"
            + f"<!-- content-sha256: sha256:{хэш} -->\n"
            + "<!-- FUM-MD-RECENCY:END -->\n"
        )

    def _снимок_поколения(сам, политика):
        корень = сам.корень / политика["целевая_область"]
        return {
            путь.relative_to(корень).as_posix(): (
                "100755" if путь.stat().st_mode & 0o111 else "100644",
                путь.read_bytes(),
            )
            for путь in sorted(корень.rglob("*"))
            if путь.is_file()
        }


import io
import json
import shutil
import unittest
from unittest import mock

import test_братиславская_проекция_памяти as основа


модуль = основа.модуль


class ПроверкаПрофилированияПроекции(unittest.TestCase):
    def _записи(сам, поток):
        return [json.loads(строка.removeprefix("FUM-PROFILE "))
                for строка in поток.getvalue().splitlines()]

    def test_отключённый_профиль_не_читает_часы_и_не_пишет(сам):
        with mock.patch.object(модуль, "perf_counter_ns") as часы, \
                mock.patch.object(модуль.sys, "stderr") as поток:
            with модуль.сеанс_профилирования(False):
                with модуль.профилировочная_метка("этап"):
                    pass
        часы.assert_not_called()
        поток.write.assert_not_called()

    def test_вложенные_повторы_различаются_и_измеряются(сам):
        поток = io.StringIO()
        with mock.patch.object(модуль.sys, "stderr", поток), \
                mock.patch.object(модуль, "perf_counter_ns", side_effect=[0, 10, 20, 35, 40, 60, 80]):
            with модуль.сеанс_профилирования(True):
                with модуль.профилировочная_метка("внешний"):
                    for _ in range(2):
                        with модуль.профилировочная_метка("повтор"):
                            pass
        записи = сам._записи(поток)
        начала = [x for x in записи if x["событие"] == "начало"]
        концы = [x for x in записи if x["событие"] == "окончание"]
        сам.assertEqual([x["родитель"] for x in начала], [None, 1, 1])
        сам.assertEqual([x["интервал"] for x in начала], [1, 2, 3])
        сам.assertEqual([x["длительность_нс"] for x in концы], [15, 20, 70])
        сам.assertTrue(all(x["исход"] == "успешно" for x in концы))

    def test_исходная_ошибка_сохраняется_и_закрывает_интервал(сам):
        поток = io.StringIO()
        ошибка = RuntimeError("исходная ошибка")
        with mock.patch.object(модуль.sys, "stderr", поток):
            with сам.assertRaises(RuntimeError) as пойманная:
                with модуль.сеанс_профилирования(True):
                    with модуль.профилировочная_метка("отказ"):
                        raise ошибка
        сам.assertIs(пойманная.exception, ошибка)
        сам.assertEqual(сам._записи(поток)[-1]["исход"], "ошибка")

    def test_неисправный_диагностический_поток_не_меняет_исход(сам):
        поток = mock.Mock()
        поток.write.side_effect = OSError("места нет")
        ошибка = RuntimeError("исходная ошибка")
        with mock.patch.object(модуль.sys, "stderr", поток):
            with модуль.сеанс_профилирования(True):
                with модуль.профилировочная_метка("успех"):
                    результат = 42
                with сам.assertRaises(RuntimeError) as пойманная:
                    with модуль.профилировочная_метка("отказ"):
                        raise ошибка
        сам.assertEqual(результат, 42)
        сам.assertIs(пойманная.exception, ошибка)

    def test_профиль_не_меняет_поколение_и_сохраняет_независимую_проверку(сам):
        фикстура = основа.ПроверкаКонтрактаБратиславскойПроекции()
        фикстура.подготовить_испытание()
        сам.addCleanup(фикстура.завершить_испытание)
        фикстура._записать("README.md", "# FUM\n")
        фикстура._зафиксировать()
        политика = фикстура._политика()
        преобразователь = фикстура._преобразователь()
        модуль.применить_поколение(фикстура.корень, политика, преобразователь)
        до = фикстура._снимок_поколения(политика)
        shutil.rmtree(фикстура.корень / политика["производное_пространство"])
        поток = io.StringIO()
        with mock.patch.object(модуль.sys, "stderr", поток), модуль.сеанс_профилирования(True):
            модуль.применить_поколение(фикстура.корень, политика, преобразователь)
            модуль.применить_поколение(фикстура.корень, политика, преобразователь)
        сам.assertEqual(до, фикстура._снимок_поколения(политика))
        начала = [x for x in сам._записи(поток) if x["событие"] == "начало"]
        сам.assertIn("независимая проверка манифеста", [x["метка"] for x in начала])
        сам.assertIn("запись и синхронизация поколения", [x["метка"] for x in начала])
        сам.assertGreaterEqual(sum(x["метка"] == "построение плана" for x in начала), 2)

    def test_профиль_включается_через_CLI_и_окружение_без_изменения_stdout(сам):
        for флаги, значение, включён in (([], "0", False), ([], "1", True),
                                      (["--профилировать"], "0", True), ([], "", False)):
            with сам.subTest(флаги=флаги, окружение=значение):
                выход, диагностика = io.StringIO(), io.StringIO()

                def команда(_аргументы):
                    with модуль.профилировочная_метка("исполнение команды"):
                        print('{"ответ":42}')
                    return 7

                with mock.patch.dict(модуль.os.environ, {"FUM_PROJECTION_PROFILE": значение}), \
                        mock.patch.object(модуль, "выполнить_команду", команда), \
                        mock.patch.object(модуль.sys, "stdout", выход), \
                        mock.patch.object(модуль.sys, "stderr", диагностика):
                    код = модуль.главная(["проверить-контракт", "--корень-репозитория", ".",
                                         "--контракт", "нечитаемая-фикстура.json", *флаги])
                сам.assertEqual(код, 7)
                сам.assertEqual(выход.getvalue(), '{"ответ":42}\n')
                сам.assertEqual(len(сам._записи(диагностика)), 2 if включён else 0)

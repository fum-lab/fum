"""Переход от принятого общего пакета к объединению форматов двух веток."""

import json
from pathlib import Path
import unittest
from unittest import mock

import test_братиславская_проекция_памяти as основа

модуль = основа.модуль
базовая = основа.ПроверкаКонтрактаБратиславскойПроекции
хэш_прежней_политики = "sha256:9f9c4a040b592396ccca722c33f0895342901dfba1ffd5a63bc9bb45c2604ac2"
путь_контракта = "совместимость/контракт-v2-до-объединения-форматов.json"


class ПроверкаПереходаОбъединённыхФорматов(unittest.TestCase):
    подготовить_испытание = базовая.подготовить_испытание
    завершить_испытание = базовая.завершить_испытание
    _выполнить_команду_контроля_версий = базовая._выполнить_команду_контроля_версий
    _записать = базовая._записать
    _зафиксировать = базовая._зафиксировать
    _преобразователь = базовая._преобразователь
    _снимок_поколения = базовая._снимок_поколения
    _записать_манифест = базовая._записать_манифест
    _проверить_переход_прежнего_v2 = базовая._проверить_переход_прежнего_v2

    def _установить_прежнее_поколение_v2(сам):
        путь = основа.СЦЕНАРИЙ.parents[1] / "tests/фикстуры/поколение-до-объединения-форматов-v2.json"
        фикстура = json.loads(путь.read_text())
        сам.assertEqual(фикстура["происхождение"], {
            "коммит": "f80bdf424350a6c07fb5e5acf25e5b252cfd03be",
            "хэш_кода": "sha256:bbdbb100da672deb22ed58380a7a0158a2b03b014c2bd0b03ed85f0f6dcd1d7f",
            "хэш_политики": хэш_прежней_политики,
        })
        for путь, данные in фикстура["исходники_hex"].items():
            сам._записать(путь, bytes.fromhex(данные))
        сам._зафиксировать()
        for путь, данные in фикстура["выходы_hex"].items():
            сам._записать(путь, bytes.fromhex(данные))
        политика = модуль.загрузить_политику(основа.СЦЕНАРИЙ.parents[1] / "контракт-v2.json")
        сам._записать_манифест(политика, фикстура["манифест"])
        return политика, фикстура, сам._преобразователь(фикстура["соответствия"])

    test_неизменный_канон_и_строгая_финальная_проверка = базовая.test_переход_прежнего_v2_при_неизменном_каноне
    test_добавленные_форматы_и_строгая_финальная_проверка = базовая.test_переход_прежнего_v2_с_добавленными_форматами_приложения
    test_повреждённые_байты_сохраняются = базовая.test_переход_прежнего_v2_сохраняет_повреждённое_дерево
    test_чужой_файл_сохраняется = базовая.test_переход_прежнего_v2_сохраняет_чужой_файл
    test_чужой_режим_сохраняется = базовая.test_переход_прежнего_v2_сохраняет_чужой_режим
    test_полные_метаданные_манифеста = базовая.test_переход_прежнего_v2_проверяет_полные_метаданные_манифеста

    def test_неизвестная_политика(сам):
        политика, фикстура, преобразователь = сам._установить_прежнее_поколение_v2()
        неизвестная = json.loads((основа.СЦЕНАРИЙ.parents[1] / путь_контракта).read_text())
        неизвестная["ограничения_пути"]["максимум_байтов_компонента"] -= 1
        план = фикстура["план"]
        план["хэш_политики"] = модуль.хэш_значения(неизвестная)
        план["исходный_снимок"]["хэш_политики"] = план["хэш_политики"]
        план["хэш_плана"] = модуль.вычислить_хэш_плана(план)
        выходы = {путь: bytes.fromhex(данные) for путь, данные in фикстура["выходы_hex"].items()}
        сам._записать_манифест(политика, модуль.сформировать_манифест(план, выходы))
        снимок = сам._снимок_поколения(политика)
        with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "политик"):
            модуль.применить_поколение(сам.корень, политика, преобразователь)
        сам.assertEqual(снимок, сам._снимок_поколения(политика))

    def test_точный_контракт_отсутствие_и_символическая_ссылка(сам):
        политика, _фикстура, преобразователь = сам._установить_прежнее_поколение_v2()
        источник = основа.СЦЕНАРИЙ.parents[1] / путь_контракта
        каталог = Path(сам.временный_каталог.name) / "код"
        контракт = каталог / путь_контракта
        контракт.parent.mkdir(parents=True)
        контракт.write_bytes(источник.read_bytes())
        снимок = сам._снимок_поколения(политика)
        with mock.patch.object(модуль, "__file__", str(каталог / "scripts/проекция.py")):
            прежняя = модуль.политика_для_доказательства_владения(политика, хэш_прежней_политики)
            сам.assertEqual(модуль.хэш_значения(прежняя), хэш_прежней_политики)
            прежняя["ограничения_пути"]["максимум_байтов_компонента"] -= 1
            контракт.write_bytes(модуль.канонические_байты(прежняя))
            with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "полный объект"):
                модуль.применить_поколение(сам.корень, политика, преобразователь)
            сам.assertEqual(сам._снимок_поколения(политика), снимок)
            контракт.unlink()
            with сам.assertRaises(модуль.ОшибкаКонтракта):
                модуль.применить_поколение(сам.корень, политика, преобразователь)
            сам.assertEqual(сам._снимок_поколения(политика), снимок)
            контракт.symlink_to(источник)
            with сам.assertRaises(модуль.ОшибкаКонтракта):
                модуль.применить_поколение(сам.корень, политика, преобразователь)
            сам.assertEqual(сам._снимок_поколения(политика), снимок)


setattr(ПроверкаПереходаОбъединённыхФорматов, "setUp", базовая.подготовить_испытание)
setattr(ПроверкаПереходаОбъединённыхФорматов, "tearDown", базовая.завершить_испытание)
del базовая

if __name__ == "__main__":
    unittest.main()

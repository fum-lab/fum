"""Приём четырёх CJS-сценариев, прежней политики и точных байтов."""

import hashlib
import json
import unittest
from unittest import mock

import test_братиславская_проекция_памяти as основа

модуль = основа.модуль
пути = (
    "Инструменты/fum-svyaznostj-rabochej-sessii/scripts/адаптер_ответа.cjs",
    "Инструменты/fum-svyaznostj-rabochej-sessii/tests/test_адаптер_ответа.cjs",
    "Инструменты/fum-svyaznostj-rabochej-sessii/tests/профиль-смешанных-ответов.cjs",
    "Инструменты/fum-svyaznostj-rabochej-sessii/tests/test_смешанный_профиль.cjs",
)


class ПроверкаПроекцииСценария(unittest.TestCase):
    _выполнить_команду_контроля_версий = основа.ПроверкаКонтрактаБратиславскойПроекции._выполнить_команду_контроля_версий
    _записать = основа.ПроверкаКонтрактаБратиславскойПроекции._записать
    _зафиксировать = основа.ПроверкаКонтрактаБратиславскойПроекции._зафиксировать
    _снимок_поколения = основа.ПроверкаКонтрактаБратиславскойПроекции._снимок_поколения
    _записать_манифест = основа.ПроверкаКонтрактаБратиславскойПроекции._записать_манифест

    def политика(сам):
        return json.loads((основа.СЦЕНАРИЙ.parents[1] / "контракт-v2.json").read_text())

    def test_точные_четыре_пути_сохраняют_байты_и_суффикс(сам):
        политика = сам.политика()
        for путь in пути:
            with сам.subTest(путь=путь):
                байты = '"use strict"; const имя = значение => значение;\n'.encode()
                сам.assertEqual(модуль.классифицировать_содержимое(сам.корень, путь, политика, байты)[1], "сохранить_байты")
                сам.assertEqual(модуль.основа_и_расширение(путь.rsplit("/", 1)[1], True, политика["сохраняемые_технические_расширения"])[1], ".cjs")

    def _преобразовать(сам, строки):
        соответствия = {"Пример":"Primer", "Инструменты":"Instrumentyi", "адаптер_ответа":"adapter_otveta",
                       "test_адаптер_ответа":"test_adapter_otveta", "test_смешанный_профиль":"test_smeshannyj_profilj",
                       "профиль-смешанных-ответов":"profilj-smeshannyh-otvetov"}
        return [соответствия.get(строка, строка) for строка in строки]

    def test_установка_независимая_проверка_повтор_и_подмена_выхода(сам):
        политика = сам.политика()
        байты = '"use strict";\r\nconst имя = значение => значение;\r\n'.encode()
        for путь in пути:
            сам._записать(путь, байты)
        сам._зафиксировать()
        модуль.применить_поколение(сам.корень, политика, сам._преобразовать)
        снимок = сам._снимок_поколения(политика)
        манифест = json.loads((сам.корень / политика["путь_манифеста"]).read_text())
        записи = [з for з in манифест["записи"] if з["исходный_путь"] in пути]
        сам.assertEqual(len(записи), 4)
        for запись in записи:
            сам.assertTrue(запись["целевой_путь"].endswith(".cjs"))
            сам.assertEqual((сам.корень / запись["целевой_путь"]).read_bytes(), байты)
            сам.assertEqual((сам.корень / запись["исходный_путь"]).read_bytes(), байты)
        модуль.проверить_манифест(сам.корень, политика, манифест, сам.корень / политика["целевая_область"], сам._преобразовать)
        модуль.применить_поколение(сам.корень, политика, сам._преобразовать)
        сам.assertEqual(сам._снимок_поколения(политика), снимок)
        подмена = байты.replace('имя'.encode(), 'слово'.encode())
        сам._записать(записи[0]["целевой_путь"], подмена)
        записи[0]["хэш_цели"] = "sha256:" + hashlib.sha256(подмена).hexdigest()
        сам._записать_манифест(политика, манифест)
        with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "Побайтовый выход"):
            модуль.проверить_манифест(сам.корень, политика, манифест, сам.корень / политика["целевая_область"], сам._преобразовать)




    def test_неизвестное_содержимое_и_латинские_объявления_закрыты(сам):
        for байты in (b"\xff", b"\0", b"const hidden = 1;", b"class A {}", b"const x = ;"):
            with сам.subTest(байты=байты):
                with сам.assertRaises(модуль.ОшибкаКонтракта):
                    модуль.классифицировать_содержимое(сам.корень, пути[0], сам.политика(), байты)

    def test_соседний_путь_не_становится_разрешённым_расширением(сам):
        for путь in (пути[0] + ".cjs", пути[0].replace("Инструменты", "инструменты"),
                     "Вложенное/" + пути[0], пути[0].replace(".cjs", ".mjs")):
            with сам.subTest(путь=путь):
                with сам.assertRaises(модуль.ОшибкаКонтракта):
                    модуль.классифицировать_содержимое(сам.корень, путь, сам.политика(), b"const value = 1;")



setattr(ПроверкаПроекцииСценария, "setUp", основа.ПроверкаКонтрактаБратиславскойПроекции.подготовить_испытание)
setattr(ПроверкаПроекцииСценария, "tearDown", основа.ПроверкаКонтрактаБратиславскойПроекции.завершить_испытание)

if __name__ == "__main__":
    unittest.main()

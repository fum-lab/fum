#!/usr/bin/env python3
"""Измеряет переход карты авторов на открытой фикстуре, без Swift."""

import argparse
import hashlib
import json
from pathlib import Path
import sys
from time import perf_counter_ns

from test_карта_авторов import ПроверкаКартыАвторов
import test_братиславская_проекция_памяти as проверки_проекции


def измерить(выход, повторы):
    каталог = Path(__file__).resolve().parent.parent
    if (проверки_проекции.СЦЕНАРИЙ.parent.parent.resolve() != каталог
        or проверки_проекции.СЦЕНАРИЙ.resolve() != (
            каталог / "scripts/братиславская_проекция_памяти.py"
        ).resolve()):
        raise ValueError("FUM_CHECKED_CODE_ROOT выбирает другой источник профиля")
    пути = [
        "контракт-v2.json",
        "scripts/братиславская_проекция_памяти.py",
        "совместимость/контракт-v2-до-карты-авторов.json",
        "tests/test_карта_авторов.py",
        "tests/test_братиславская_проекция_памяти.py",
        "tests/профиль-карты-авторов.py",
        "tests/test_профиль_карты_авторов.py",
        "tests/фикстуры/поколение-до-карты-авторов-v2.json",
        "../fum-pereimenovaniye-fajla-s-obnovleniyem-ssyilok/scripts/pereimenovatj-fajl-s-obnovleniyem-ssyilok.py",
        "../fum-proyektnyiye-fajlyi/scripts/project_files.py",
        "../fum-struktura-papok-zaprosov/scripts/request_folder_layout.py",
    ]
    хэши = {путь: hashlib.sha256((каталог / путь).read_bytes()).hexdigest()
            for путь in пути}
    измерения = []
    for номер in range(повторы):
        случай = ПроверкаКартыАвторов()
        try:
            фикстура, модуль, политика, данные = случай.прежнее_поколение()
            преобразователь = фикстура._преобразователь(данные["соответствия"])
            фикстура._записать(".mailmap", "# Ёж\r\n".encode("utf-8"))
            начало = perf_counter_ns()
            модуль.применить_поколение(фикстура.корень, политика, преобразователь)
            переход = perf_counter_ns() - начало
            манифест = модуль.загрузить_машинные_данные(
                фикстура.корень / политика["путь_манифеста"], "манифест"
            )
            начало = perf_counter_ns()
            модуль.проверить_манифест(
                фикстура.корень, политика, манифест,
                фикстура.корень / политика["целевая_область"], преобразователь,
            )
            проверка = perf_counter_ns() - начало
            снимок = фикстура._снимок_поколения(политика)
            начало = perf_counter_ns()
            модуль.применить_поколение(фикстура.корень, политика, преобразователь)
            повтор = perf_counter_ns() - начало
            if снимок != фикстура._снимок_поколения(политика):
                raise ValueError("Повтор изменил поколение")
            измерения.append({
                "номер": номер + 1,
                "переход_наносекунды": переход,
                "проверка_наносекунды": проверка,
                "повтор_наносекунды": повтор,
                "хэш_инвентаря": манифест["исходный_снимок"]["хэш_инвентаря"],
                "манифест_sha256": hashlib.sha256(
                    (фикстура.корень / политика["путь_манифеста"]).read_bytes()
                ).hexdigest(),
                "исход": "успех",
            })
        finally:
            случай.doCleanups()
    if хэши != {путь: hashlib.sha256((каталог / путь).read_bytes()).hexdigest()
               for путь in пути}:
        raise ValueError("Измеряемые исходники изменились во время профиля")
    результат = {
        "схема": "fum.профиль-карты-авторов.1",
        "python": sys.version,
        "хэши_исходников": хэши,
        "измерения": измерения,
        "граница": "Подготовка и очистка фикстур, чтение манифеста между стадиями и запись профиля исключены. Swift заменён фиксированным преобразованием открытой фикстуры. Интервалы последовательны, время полного репозитория и ускорение относительно прежней реализации не измерены.",
    }
    выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"повторы": повторы, "исход": "успех"}, ensure_ascii=False))


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    разбор.add_argument("--повторов", type=int, default=3, choices=range(1, 101))
    параметры = разбор.parse_args()
    измерить(параметры.выход, параметры.повторов)

def измерить_классификацию(назначение):
    """Пять серий по тысяче вызовов без Git, Swift и записи поколения."""
    выбранная = политика()
    данные = образец.encode()
    замеры = []
    исходы = set()
    for _ in range(5):
        начало = perf_counter_ns()
        for _ in range(1000):
            try:
                модуль.классифицировать_содержимое(Path.cwd(), путь_адаптера, выбранная, данные)
                исходы.add("принят")
            except модуль.ОшибкаКонтракта:
                исходы.add("отказ")
        замеры.append((perf_counter_ns() - начало) / 1000)
    результат = {"схема": "fum.профиль-конечного-адаптера.1", "повторов_серии": 1000,
                 "серии_нс_на_вызов": замеры, "медиана_нс": statistics.median(замеры),
                 "исходы": sorted(исходы), "байтов_входа": len(данные),
                 "sha256_входа": hashlib.sha256(данные).hexdigest(),
                 "sha256_реализации": hashlib.sha256(основа.СЦЕНАРИЙ.read_bytes()).hexdigest(),
                 "sha256_сценария": hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    Path(назначение).write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(результат, ensure_ascii=False))

"""Граница единственного конечного адаптера; прочие форматы не расширяются."""

import hashlib
import json
from pathlib import Path
import statistics
from time import perf_counter_ns
import unittest

import test_братиславская_проекция_памяти as основа


модуль = основа.модуль
путь_адаптера = "Инструменты/fum-reyestr-planirovaniya/scripts/адаптер-codex.js"
образец = (
    "async (возможности, вход) => {\n"
    "  const допуск = await возможности.подготовить(вход);\n"
    "  if (допуск.разрешён_вызов) {\n"
    "    const ответ = await возможности.исполнить(допуск);\n"
    "    return await возможности.сохранить(допуск, ответ);\n"
    "  }\n"
    "  return допуск;\n"
    "}\n"
)


def политика():
    return json.loads((основа.СЦЕНАРИЙ.parents[1] / "контракт-v2.json").read_text())


class ПроверкаПроекцииКонечногоАдаптера(unittest.TestCase):
    _выполнить_команду_контроля_версий = основа.ПроверкаКонтрактаБратиславскойПроекции._выполнить_команду_контроля_версий
    _записать = основа.ПроверкаКонтрактаБратиславскойПроекции._записать
    _зафиксировать = основа.ПроверкаКонтрактаБратиславскойПроекции._зафиксировать
    _снимок_поколения = основа.ПроверкаКонтрактаБратиславскойПроекции._снимок_поколения
    _записать_манифест = основа.ПроверкаКонтрактаБратиславскойПроекции._записать_манифест

    def _преобразовать(сам, строки):
        соответствия = {"Пример": "Primer", "Инструменты": "Instrumentyi", "адаптер-codex": "adapter-codex",
                       "адаптер-codex.js": "adapter-codex.js"}
        return [соответствия.get(строка, строка) for строка in строки]

    def _план(сам):
        return модуль.построить_план(сам.корень, политика(), сам._преобразовать)

    def test_точный_адаптер_сохраняет_байты_в_плане_поколении_и_повторе(сам):
        исходник = сам._записать(путь_адаптера, образец)
        сам._зафиксировать()
        план = сам._план()
        запись = план["записи"][0]
        сам.assertEqual(запись["действие_содержимого"], "сохранить_байты")
        сам.assertEqual(запись["целевой_путь"],
                       "Proyekcii/Bratislavskaya-pamyatj/fajlyi/Instrumentyi/"
                       "fum-reyestr-planirovaniya/scripts/adapter-codex.js")
        выходы = модуль.сформировать_выходы(сам.корень, план, сам._преобразовать)
        сам.assertEqual(выходы[запись["целевой_путь"]], образец.encode())
        модуль.применить_поколение(сам.корень, политика(), сам._преобразовать)
        снимок = сам._снимок_поколения(политика())
        манифест = json.loads((сам.корень / политика()["путь_манифеста"]).read_text())
        результат = модуль.проверить_манифест(
            сам.корень, политика(), манифест,
            сам.корень / политика()["целевая_область"], сам._преобразовать)
        сам.assertEqual(результат["состояние"], "действителен")
        модуль.применить_поколение(сам.корень, политика(), сам._преобразовать)
        сам.assertEqual(сам._снимок_поколения(политика()), снимок)
        сам.assertEqual(исходник.read_bytes(), образец.encode())

    def test_иной_путь_или_расширение_адаптера_закрывает_план(сам):
        for путь in (путь_адаптера.replace("адаптер", "другой"),
                     путь_адаптера.replace("Инструменты", "инструменты"),
                     "Вложенное/" + путь_адаптера, путь_адаптера + ".js",
                     путь_адаптера[:-3] + ".mjs", путь_адаптера[:-3] + ".cjs"):
            with сам.subTest(путь=путь):
                with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "Неизвестный формат"):
                    модуль.классифицировать_содержимое(сам.корень, путь, политика(), образец.encode())

    def test_полный_шаблон_проверяется_до_двоичного_исключения(сам):
        варианты = (образец + "// комментарий\n", образец + "import x from 'x';\n",
                    образец.replace("return допуск;", 'return "допуск";'),
                    образец.replace("return допуск;", "return вход;"),
                    образец.replace("return await", "return\n await"))
        for данные in [текст.encode() for текст in варианты] + [b"\xff", b"\0"]:
            with сам.subTest(данные=данные[:40]):
                with сам.assertRaises(модуль.ОшибкаКонтракта):
                    модуль.классифицировать_содержимое(сам.корень, путь_адаптера, политика(), данные)

    def test_точный_формат_не_самозаверяет_изменённые_байты(сам):
        сам._записать(путь_адаптера, образец)
        сам._зафиксировать()
        план = сам._план()
        выходы = модуль.сформировать_выходы(сам.корень, план, сам._преобразовать)
        целевой = план["записи"][0]["целевой_путь"]
        сам._записать(целевой, образец.replace("возможности", "средства"))
        манифест = модуль.сформировать_манифест(план, выходы)
        манифест["записи"][0]["хэш_цели"] = "sha256:" + hashlib.sha256((сам.корень / целевой).read_bytes()).hexdigest()
        сам._записать_манифест(политика(), манифест)
        with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "Побайтовый выход"):
            модуль.проверить_манифест(сам.корень, политика(), манифест,
                                     сам.корень / политика()["целевая_область"], сам._преобразовать)

    def test_схема_и_формат_точного_пути_совпадают(сам):
        путь = основа.СЦЕНАРИЙ.parents[1] / "схемы/схема-плана-v2.json"
        схема = json.loads(путь.read_text())
        раздел = схема["$defs"]["форматная_политика"]["properties"]["прочие_точные_форматы"]["properties"]
        сам.assertEqual(раздел["точные_пути"]["const"], политика()["форматы"]["прочие_точные_форматы"]["точные_пути"])
        сам.assertIn(путь_адаптера, раздел["точные_пути"]["const"])
        сам.assertNotIn(".js", политика()["форматы"]["код"]["расширения"])

    def test_нетекстовый_иной_файл_сохраняет_прежнюю_политику(сам):
        класс, действие, _ = модуль.классифицировать_содержимое(
            сам.корень, "данные.bin", политика(), b"\xff\0")
        сам.assertEqual((класс, действие), ("двоичный_или_нетекстовый", "сохранить_байты"))

    def _прежнее_поколение(сам):
        фикстура = json.loads((основа.СЦЕНАРИЙ.parents[1] / "tests/фикстуры/прежнее-поколение-v2.json").read_text())
        сам.assertEqual(фикстура["происхождение"]["хэш_политики"],
                       "sha256:9f262153c9de986270cec76ad3c37da34c99ace0c187474ba8a1bc736222220a")
        сам.assertNotIn(путь_адаптера, фикстура["манифест"]["форматная_политика"]["прочие_точные_форматы"]["точные_пути"])
        for путь, данные in фикстура["исходники_hex"].items():
            сам._записать(путь, bytes.fromhex(данные))
        сам._зафиксировать()
        for путь, данные in фикстура["выходы_hex"].items():
            сам._записать(путь, bytes.fromhex(данные))
        сам._записать_манифест(политика(), фикстура["манифест"])
        return фикстура

    def test_прежнее_версии_2_переходит_к_точному_адаптеру_без_ослабления_проверки(сам):
        фикстура = сам._прежнее_поколение()
        сам._записать(путь_адаптера, образец)
        with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "хэш политики изменился"):
            модуль.проверить_манифест(сам.корень, политика(), фикстура["манифест"],
                                     сам.корень / политика()["целевая_область"], сам._преобразовать)
        модуль.применить_поколение(сам.корень, политика(), сам._преобразовать)
        манифест = json.loads((сам.корень / политика()["путь_манифеста"]).read_text())
        сам.assertEqual(манифест["хэш_политики"], модуль.хэш_значения(политика()))
        сам.assertEqual(манифест["форматная_политика"], политика()["форматы"])
        сам.assertEqual(len(манифест["записи"]), 2)
        for запись in манифест["записи"]:
            сам.assertEqual((сам.корень / запись["целевой_путь"]).read_bytes(),
                            (сам.корень / запись["исходный_путь"]).read_bytes())
        модуль.проверить_манифест(сам.корень, политика(), манифест,
                                 сам.корень / политика()["целевая_область"], сам._преобразовать)
        снимок = сам._снимок_поколения(политика())
        модуль.применить_поколение(сам.корень, политика(), сам._преобразовать)
        сам.assertEqual(сам._снимок_поколения(политика()), снимок)

    def test_переход_сохраняет_дерево_при_подмене_старого_манифеста(сам):
        фикстура = сам._прежнее_поколение()
        for поле, замена in (("хэш_политики", "sha256:" + "0" * 64),
                            ("форматная_политика", политика()["форматы"])):
            with сам.subTest(поле=поле):
                сам._записать_манифест(политика(), {**фикстура["манифест"], поле: замена})
                снимок = сам._снимок_поколения(политика())
                with сам.assertRaises(модуль.ОшибкаКонтракта):
                    модуль.применить_поколение(сам.корень, политика(), сам._преобразовать)
                сам.assertEqual(сам._снимок_поколения(политика()), снимок)



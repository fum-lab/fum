#!/usr/bin/env python3
"""Измеряет выбор политики и один синтетический переход; Swift не вызывается."""

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import platform
import statistics
import sys
from time import perf_counter_ns


def измерить(выход, поколение="до-форматов-приложения"):
    каталог = Path(__file__).resolve().parents[1]
    sys.path.insert(0, str(каталог))
    объединение = поколение == "до-объединения-форматов"
    путь = каталог / ("test_переход_объединённых_форматов.py" if объединение else "test_братиславская_проекция_памяти.py")
    спецификация = importlib.util.spec_from_file_location("проверки_перехода", путь)
    проверки = importlib.util.module_from_spec(спецификация)
    спецификация.loader.exec_module(проверки)
    модуль = проверки.модуль
    сценарий = проверки.основа.СЦЕНАРИЙ if объединение else проверки.СЦЕНАРИЙ
    политика = модуль.загрузить_политику(сценарий.parent.parent / "контракт-v2.json")
    класс_проверки = проверки.ПроверкаПереходаОбъединённыхФорматов if объединение else проверки.ПроверкаКонтрактаБратиславскойПроекции
    хэш_прежней = проверки.хэш_прежней_политики if объединение else модуль.ХЭШ_ПОЛИТИКИ_ДО_ФОРМАТОВ_ПРИЛОЖЕНИЯ
    измерения = {}
    for название, хэш in (("действующая_политика", модуль.хэш_значения(политика)),
                          ("прежняя_политика", хэш_прежней)):
        выборки = []
        for _повтор in range(5):
            начало = perf_counter_ns()
            for _вызов in range(1000):
                модуль.политика_для_доказательства_владения(политика, хэш)
            выборки.append((perf_counter_ns() - начало) / 1000)
        измерения[название] = {"выборки_нс_на_вызов": выборки, "медиана_нс": statistics.median(выборки)}
    переходы = []
    for _повтор in range(5):
        проверка = класс_проверки()
        проверка.подготовить_испытание()
        try:
            политика, _фикстура, преобразователь = проверка._установить_прежнее_поколение_v2()
            начало = perf_counter_ns()
            модуль.применить_поколение(проверка.корень, политика, преобразователь)
            переходы.append(perf_counter_ns() - начало)
            манифест = json.loads((проверка.корень / политика["путь_манифеста"]).read_text())
            модуль.проверить_манифест(проверка.корень, политика, манифест,
                                    проверка.корень / политика["целевая_область"], преобразователь)
        finally:
            проверка.завершить_испытание()
    результат = {"схема": "fum.профиль-перехода-прежнего-v2.2", "Python": platform.python_version(),
                 "поколение": поколение, "происхождение_фикстуры": _фикстура["происхождение"],
                 "хэш_прежней_политики": хэш_прежней,
                 "платформа": platform.platform(), "хэш_кода": "sha256:" + hashlib.sha256(сценарий.read_bytes()).hexdigest(),
                 "хэш_политики": модуль.хэш_значения(политика), "выбор_политики": измерения,
                 "переход": {"выборки_нс": переходы, "медиана_нс": statistics.median(переходы)},
                 "граница": "5 × 1000 вызовов выбора, прогретая файловая система; 5 переходов одного .txt, без подготовки фикстуры, последующей независимой проверки и Swift"}
    выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"выбор_прежней_нс": измерения["прежняя_политика"]["медиана_нс"],
                      "переход_нс": statistics.median(переходы)}, ensure_ascii=False))


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    разбор.add_argument("--поколение", choices=("до-форматов-приложения", "до-объединения-форматов"), default="до-форматов-приложения")
    параметры = разбор.parse_args()
    измерить(параметры.выход, параметры.поколение)

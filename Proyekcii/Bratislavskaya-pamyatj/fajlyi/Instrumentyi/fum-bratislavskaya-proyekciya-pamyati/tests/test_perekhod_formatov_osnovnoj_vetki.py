"""Настоящие закреплённые поколения M/L и совместное владение Git-стадиями."""

import json
from pathlib import Path
import tempfile
import unittest
from unittest import mock

import test_братиславская_проекция_памяти as основа


class ПроверкаПереходаФорматов(unittest.TestCase):
    def подготовить(сам):
        сам.фикстура = основа.ПроверкаКонтрактаБратиславскойПроекции()
        сам.фикстура.подготовить_испытание()
        сам.addCleanup(сам.фикстура.завершить_испытание)
        сам.модуль = основа.модуль
        сам.каталог = основа.СЦЕНАРИЙ.parent.parent
        сам.политика = сам.модуль.загрузить_политику(сам.каталог / "контракт-v2.json")
        сам.assertEqual(сам.модуль.хэш_значения(сам.политика),
                        "sha256:519247e248fca466e3344aaf256e04c7df31c6fdcc41fd5c8ad80858643b34bc")
        сам.преобразователь = сам.фикстура._преобразователь({"Пример": "Primer"})

    def прочитать(сам, имя):
        данные = json.loads((сам.каталог / "tests/фикстуры" / имя).read_text())
        ведущая = имя == "поколение-ведущей-v2.json"
        ожидаемое = {
            "коммит": "62a8dfc8c8182d1d37cce9c0d1b86717f52303e0" if ведущая else "9d01af6de4fc2f1c9265ee8805cda4998322e004",
            "хэш_кода": "sha256:fe09bb63c61f5fcce60037d01e772e72ed6c04f1166753938cabb8f926032dd9" if ведущая else "sha256:a430c52b383ec1196477a4c721f6931384e5088acf5d37c35a899c01ca807f6a",
            "хэш_политики": "sha256:519247e248fca466e3344aaf256e04c7df31c6fdcc41fd5c8ad80858643b34bc" if ведущая else "sha256:43652412d709576d3cbda4fa22538a6ad030789f6224315b52c97dfae4e96f3c",
        }
        сам.assertEqual(данные["происхождение"], ожидаемое)
        сам.assertEqual(данные["манифест"]["хэш_политики"], ожидаемое["хэш_политики"])
        сам.assertEqual(данные["план"]["хэш_политики"], ожидаемое["хэш_политики"])
        return данные

    def поместить(сам, данные):
        for набор in ("исходники_hex", "выходы_hex"):
            for путь, байты in данные[набор].items():
                сам.фикстура._записать(путь, bytes.fromhex(байты))
        сам.фикстура._записать_манифест(сам.политика, данные["манифест"])

    def установить(сам, имя):
        данные = сам.прочитать(имя)
        for путь, байты in данные["исходники_hex"].items():
            сам.фикстура._записать(путь, bytes.fromhex(байты))
        сам.фикстура._зафиксировать()
        сам.поместить(данные)
        return данные

    def проверить_текущее(сам):
        манифест = сам.модуль.загрузить_машинные_данные(
            сам.фикстура.корень / сам.политика["путь_манифеста"], "манифест")
        сам.модуль.проверить_манифест(
            сам.фикстура.корень, сам.политика, манифест,
            сам.фикстура.корень / сам.политика["целевая_область"], сам.преобразователь)
        сам.assertEqual(манифест["хэш_политики"], сам.модуль.хэш_значения(сам.политика))
        return манифест

    def test_полная_основная_ветка_переходит_к_выбранной_политике(сам):
        сам.подготовить()
        сам.установить("поколение-master-v2.json")
        with сам.assertRaisesRegex(сам.модуль.ОшибкаКонтракта, "хэш политики изменился"):
            сам.проверить_текущее()
        карта = сам.прочитать("поколение-ведущей-v2.json")["исходники_hex"][".mailmap"]
        сам.фикстура._записать(".mailmap", bytes.fromhex(карта))
        сам.модуль.применить_поколение(сам.фикстура.корень, сам.политика, сам.преобразователь)
        манифест = сам.проверить_текущее()
        сам.assertEqual({з["исходный_путь"] for з in манифест["записи"]}, {"Пример.txt", ".mailmap"})
        снимок = сам.фикстура._снимок_поколения(сам.политика)
        сам.модуль.применить_поколение(сам.фикстура.корень, сам.политика, сам.преобразователь)
        сам.assertEqual(сам.фикстура._снимок_поколения(сам.политика), снимок)

    def test_полное_поколение_ведущей_уже_принимается_без_перехода(сам):
        сам.подготовить()
        сам.установить("поколение-ведущей-v2.json")
        сам.проверить_текущее()
        снимок = сам.фикстура._снимок_поколения(сам.политика)
        сам.модуль.применить_поколение(сам.фикстура.корень, сам.политика, сам.преобразователь)
        сам.assertEqual(сам.фикстура._снимок_поколения(сам.политика), снимок)

    def test_неизвестная_политика_не_получает_мост(сам):
        сам.подготовить()
        чужая = dict(сам.политика)
        чужая["ограничения_пути"] = {**чужая["ограничения_пути"], "максимум_байтов_пути": 999}
        with сам.assertRaisesRegex(сам.модуль.ОшибкаКонтракта, "известной политике"):
            сам.модуль.политика_для_доказательства_владения(сам.политика, сам.модуль.хэш_значения(чужая))

    def test_повреждение_отсутствие_и_ссылка_моста_сохраняют_поколение(сам):
        сам.подготовить()
        сам.установить("поколение-master-v2.json")
        снимок = сам.фикстура._снимок_поколения(сам.политика)
        путь_моста = "совместимость/контракт-v2-до-сценариев-и-карты-авторов.json"
        чтение = сам.модуль.безопасно_прочитать_обычный_файл
        with tempfile.TemporaryDirectory() as каталог:
            корень = Path(каталог)
            мост = корень / путь_моста
            мост.parent.mkdir()
            def прочитать(начало, путь):
                return чтение(корень if путь == путь_моста else начало, путь)
            for вариант in ("подмена", "отсутствие", "ссылка"):
                with сам.subTest(вариант=вариант):
                    if вариант == "подмена":
                        подмена = json.loads((сам.каталог / путь_моста).read_text())
                        подмена["ограничения_пути"]["максимум_байтов_компонента"] -= 1
                        мост.write_text(json.dumps(подмена))
                    elif вариант == "отсутствие":
                        мост.unlink()
                    else:
                        мост.symlink_to(сам.каталог / путь_моста)
                    with mock.patch.object(сам.модуль, "безопасно_прочитать_обычный_файл", side_effect=прочитать):
                        with сам.assertRaises(сам.модуль.ОшибкаКонтракта):
                            сам.модуль.применить_поколение(сам.фикстура.корень, сам.политика, сам.преобразователь)
                    сам.assertEqual(сам.фикстура._снимок_поколения(сам.политика), снимок)

    def зафиксировать_поколение(сам, данные):
        команда = сам.фикстура._выполнить_команду_контроля_версий
        команда("add", "--", *данные["исходники_hex"])
        команда("add", "-f", "-A", "--", "Proyekcii")
        команда("commit", "-q", "-m", "Закрепить тестовое поколение")

    def test_настоящие_стадии_основной_и_ведущей_проверяются_вместе(сам):
        сам.подготовить()
        команда = сам.фикстура._выполнить_команду_контроля_версий
        база = сам.установить("поколение-master-v2.json")
        сам.зафиксировать_поколение(база)
        основа_слияния = команда("rev-parse", "HEAD").stdout.strip()
        команда("switch", "-q", "-c", "сторона-master")
        изменённая = сам.прочитать("поколение-master-изменённое-v2.json")
        сам.поместить(изменённая)
        сам.зафиксировать_поколение(изменённая)
        команда("switch", "-q", "-c", "ведущая", основа_слияния)
        ведущая = сам.прочитать("поколение-ведущей-v2.json")
        сам.поместить(ведущая)
        сам.зафиксировать_поколение(ведущая)
        результат = команда("merge", "--no-ff", "--no-commit", "сторона-master", проверить=False)
        сам.assertNotEqual(результат.returncode, 0)
        путь = сам.политика["путь_манифеста"]
        стадии = сам.модуль.прочитать_стадии_индекса_проекции(сам.фикстура.корень)
        сам.assertEqual(set(стадии[путь]), {"1", "2", "3"})
        for номер, данные in (("1", база), ("2", ведущая), ("3", изменённая)):
            фактический = json.loads(команда("show", f":{номер}:{путь}").stdout)
            сам.assertEqual(фактический, данные["манифест"])
        сам.модуль.снимок_конфликтного_поколения(сам.фикстура.корень, сам.политика)
        сам.модуль.применить_поколение(сам.фикстура.корень, сам.политика, сам.преобразователь)
        with сам.assertRaisesRegex(сам.модуль.ОшибкаКонтракта, "конфликтные стадии"):
            сам.проверить_текущее()
        команда("add", "-f", "-A", "--", "Proyekcii")
        сам.проверить_текущее()
        сам.assertEqual((сам.фикстура.корень / "Пример.txt").read_bytes(),
                        bytes.fromhex(изменённая["исходники_hex"]["Пример.txt"]))
        сам.assertEqual((сам.фикстура.корень / ".mailmap").read_bytes(),
                        bytes.fromhex(ведущая["исходники_hex"][".mailmap"]))


if __name__ == "__main__":
    unittest.main()

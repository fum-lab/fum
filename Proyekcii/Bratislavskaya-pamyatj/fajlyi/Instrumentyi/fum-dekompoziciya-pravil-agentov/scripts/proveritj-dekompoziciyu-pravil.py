#!/usr/bin/env python3

import argparse
from collections import Counter
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import subprocess
import sys
from typing import Any, Sequence


СХЕМА = "fum.декомпозиция-правил-агентов.1"
ШАБЛОН_ХЭША = re.compile(r"sha256:[0-9a-f]{64}\Z")
ШАБЛОН_МАРШРУТА = re.compile(
    r"^<!-- FUM-МАРШРУТ: (?P<идентификатор>[^ ]+) =>(?P<пути>.*?) -->$",
    re.MULTILINE,
)
ШАБЛОН_МЕТКИ_ПРАВИЛА = "<!-- FUM-ПРАВИЛО: {идентификатор} -->"
ШАБЛОН_СВЕЖЕСТИ = re.compile(
    r"\n?<!-- FUM-MD-RECENCY:BEGIN -->.*?"
    r"<!-- FUM-MD-RECENCY:END -->\s*\Z",
    re.DOTALL,
)


class ОшибкаПроверки(Exception):
    pass


def хэш_байтов(байты: bytes) -> str:
    return "sha256:" + hashlib.sha256(байты).hexdigest()


def хэш_содержания_разметки(текст: str) -> str:
    содержание = ШАБЛОН_СВЕЖЕСТИ.sub("", текст)
    return хэш_байтов(содержание.encode("utf-8"))


def прочитать_инвентарь(путь: Path) -> dict[str, Any]:
    try:
        данные = json.loads(путь.read_text(encoding="utf-8"))
    except OSError as ошибка:
        raise ОшибкаПроверки(f"инвентарь не найден или не читается: {ошибка}") from ошибка
    except json.JSONDecodeError as ошибка:
        raise ОшибкаПроверки(f"инвентарь содержит некорректный JSON: {ошибка}") from ошибка
    if not isinstance(данные, dict):
        raise ОшибкаПроверки("корень инвентаря должен быть JSON-объектом")
    return данные


def проверить_точный_локальный_путь(
    корень: Path,
    значение: Any,
    *,
    обычный_файл: bool = True,
) -> Path:
    if not isinstance(значение, str) or not значение:
        raise ОшибкаПроверки("путь должен быть непустой строкой")
    if "\\" in значение or "://" in значение:
        raise ОшибкаПроверки(f"путь {значение!r} не является локальным POSIX-путём")
    чистый = PurePosixPath(значение)
    if чистый.is_absolute() or any(часть in ("", ".", "..") for часть in чистый.parts):
        raise ОшибкаПроверки(f"путь {значение!r} выходит из локального пространства имён")

    текущий = корень
    for часть in чистый.parts:
        try:
            имена = {запись.name for запись in os.scandir(текущий)}
        except OSError as ошибка:
            raise ОшибкаПроверки(f"путь {значение!r} не найден: {ошибка}") from ошибка
        if часть not in имена:
            похожие = sorted(имя for имя in имена if имя.casefold() == часть.casefold())
            if похожие:
                raise ОшибкаПроверки(
                    f"путь {значение!r} имеет неверный регистр компонента {часть!r}; "
                    f"фактически: {похожие[0]!r}"
                )
            raise ОшибкаПроверки(f"путь {значение!r} не найден")
        текущий = текущий / часть
        try:
            режим = текущий.lstat().st_mode
        except OSError as ошибка:
            raise ОшибкаПроверки(f"путь {значение!r} не найден: {ошибка}") from ошибка
        if stat.S_ISLNK(режим):
            raise ОшибкаПроверки(
                f"путь {значение!r} содержит компонент, являющийся символической ссылкой"
            )

    try:
        разрешённый = текущий.resolve(strict=True)
        разрешённый.relative_to(корень)
    except (OSError, ValueError) as ошибка:
        raise ОшибкаПроверки(f"путь {значение!r} разрешается за пределы checkout") from ошибка
    if обычный_файл and not текущий.is_file():
        raise ОшибкаПроверки(f"путь {значение!r} не является обычным файлом")
    return текущий


def потребовать_список(объект: dict[str, Any], поле: str) -> list[Any]:
    значение = объект.get(поле)
    if not isinstance(значение, list):
        raise ОшибкаПроверки(f"поле {поле!r} должно быть массивом")
    return значение


def индексировать_по_идентификатору(
    элементы: list[Any],
    поле: str,
) -> dict[str, dict[str, Any]]:
    результат: dict[str, dict[str, Any]] = {}
    for номер, элемент in enumerate(элементы):
        if not isinstance(элемент, dict):
            raise ОшибкаПроверки(f"{поле}[{номер}] должен быть объектом")
        идентификатор = элемент.get("идентификатор")
        if not isinstance(идентификатор, str) or not идентификатор:
            raise ОшибкаПроверки(f"{поле}[{номер}]: идентификатор отсутствует")
        if идентификатор in результат:
            raise ОшибкаПроверки(f"{поле}: идентификатор {идентификатор!r} повторён")
        результат[идентификатор] = элемент
    return результат


def проверить_компактность_корня(
    корневой_текст: str,
    ограничения: Any,
) -> None:
    if not isinstance(ограничения, dict):
        raise ОшибкаПроверки("ограничения корня должны быть объектом")
    фактические = {
        "строк": len(корневой_текст.splitlines()),
        "unicode_символов": len(корневой_текст),
        "байтов": len(корневой_текст.encode("utf-8")),
    }
    for поле, значение in фактические.items():
        предел = ограничения.get(поле)
        if not isinstance(предел, int) or предел <= 0:
            raise ОшибкаПроверки(f"ограничение компактности {поле!r} некорректно")
        if значение > предел:
            raise ОшибкаПроверки(
                f"корень нарушает компактность: {поле}={значение}, предел={предел}"
            )


def разобрать_корневые_маршруты(текст: str) -> dict[str, list[str]]:
    маршруты: dict[str, list[str]] = {}
    for совпадение in ШАБЛОН_МАРШРУТА.finditer(текст):
        идентификатор = совпадение.group("идентификатор")
        if идентификатор in маршруты:
            raise ОшибкаПроверки(f"корневой маршрут {идентификатор!r} повторён")
        сырые_пути = совпадение.group("пути").strip()
        пути = [] if not сырые_пути else [путь.strip() for путь in сырые_пути.split(";")]
        if any(not путь for путь in пути) or len(пути) != len(set(пути)):
            raise ОшибкаПроверки(f"корневой маршрут {идентификатор!r} содержит повтор или пустой путь")
        маршруты[идентификатор] = пути
    return маршруты


def прочитать_исходный_снимок(
    корень: Path,
    снимок: Any,
) -> bytes | None:
    if not isinstance(снимок, dict):
        raise ОшибкаПроверки("исходный снимок должен быть объектом")
    for поле in ("строк", "unicode_символов", "байтов"):
        if not isinstance(снимок.get(поле), int) or снимок[поле] < 0:
            raise ОшибкаПроверки(f"исходный снимок: поле {поле!r} некорректно")
    if ШАБЛОН_ХЭША.fullmatch(str(снимок.get("sha256", ""))) is None:
        raise ОшибкаПроверки("исходный снимок: sha256 некорректен")

    if not (корень / ".git").exists():
        return None
    коммит = снимок.get("commit")
    объект_снимка = снимок.get("blob")
    if not isinstance(коммит, str) or re.fullmatch(r"[0-9a-f]{40}", коммит) is None:
        raise ОшибкаПроверки("исходный снимок: commit должен быть полным OID")
    if not isinstance(объект_снимка, str) or re.fullmatch(r"[0-9a-f]{40}", объект_снимка) is None:
        raise ОшибкаПроверки("исходный снимок: blob должен быть полным OID")
    содержимое = subprocess.run(
        ["git", "-C", str(корень), "show", f"{коммит}:AGENTS.md"],
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if содержимое.returncode != 0:
        raise ОшибкаПроверки("исходный снимок AGENTS.md недоступен в указанном commit")
    объект = subprocess.run(
        ["git", "-C", str(корень), "rev-parse", f"{коммит}:AGENTS.md"],
        check=False,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if объект.returncode != 0 or объект.stdout.strip() != объект_снимка:
        raise ОшибкаПроверки("исходный снимок: Git blob не совпадает")
    байты = содержимое.stdout
    try:
        текст = байты.decode("utf-8")
    except UnicodeDecodeError as ошибка:
        raise ОшибкаПроверки("исходный AGENTS.md не является UTF-8") from ошибка
    фактические = {
        "строк": len(текст.splitlines()),
        "unicode_символов": len(текст),
        "байтов": len(байты),
        "sha256": хэш_байтов(байты),
    }
    for поле, значение in фактические.items():
        if снимок.get(поле) != значение:
            raise ОшибкаПроверки(
                f"исходный снимок: {поле} не совпадает ({снимок.get(поле)!r} != {значение!r})"
            )
    return байты


def проверить_исходные_единицы(
    элементы: list[Any],
    исходные_байты: bytes | None,
    заявлено_байтов: int,
) -> dict[str, dict[str, Any]]:
    индекс = индексировать_по_идентификатору(элементы, "исходные_единицы")
    диапазоны: set[tuple[int, int]] = set()
    for идентификатор, элемент in индекс.items():
        начало = элемент.get("начало_байта")
        конец = элемент.get("конец_байта")
        хэш = элемент.get("sha256")
        if (
            not isinstance(начало, int)
            or not isinstance(конец, int)
            or начало < 0
            or конец <= начало
            or конец > заявлено_байтов
        ):
            raise ОшибкаПроверки(f"исходная единица {идентификатор}: диапазон некорректен")
        if (начало, конец) in диапазоны:
            raise ОшибкаПроверки(f"исходная единица {идентификатор}: диапазон повторён")
        диапазоны.add((начало, конец))
        if ШАБЛОН_ХЭША.fullmatch(str(хэш)) is None:
            raise ОшибкаПроверки(f"исходная единица {идентификатор}: sha256 некорректен")
        if исходные_байты is not None:
            if хэш_байтов(исходные_байты[начало:конец]) != хэш:
                raise ОшибкаПроверки(f"исходная единица {идентификатор}: хэш диапазона не совпадает")
    упорядоченные = sorted(диапазоны)
    ожидаемое_начало = 0
    for начало, конец in упорядоченные:
        if начало != ожидаемое_начало:
            raise ОшибкаПроверки(
                "исходный инвентарь покрыт неполно: "
                f"ожидалось начало {ожидаемое_начало}, получено {начало}"
            )
        ожидаемое_начало = конец
    if ожидаемое_начало != заявлено_байтов:
        raise ОшибкаПроверки(
            "исходный инвентарь покрыт неполно: "
            f"последний байт={ожидаемое_начало}, ожидалось={заявлено_байтов}"
        )
    return индекс


def проверить_структуру(
    корень: Path,
    манифест: dict[str, Any],
) -> tuple[dict[str, list[str]], list[str]]:
    if манифест.get("схема") != СХЕМА:
        raise ОшибкаПроверки(f"ожидалась схема {СХЕМА!r}")
    корневой_путь = проверить_точный_локальный_путь(корень, "AGENTS.md")
    корневой_текст = корневой_путь.read_text(encoding="utf-8")
    проверить_компактность_корня(корневой_текст, манифест.get("ограничения_корня"))

    темы = индексировать_по_идентификатору(потребовать_список(манифест, "темы"), "темы")
    пути_тем: dict[str, dict[str, Any]] = {}
    тексты: dict[str, str] = {"AGENTS.md": корневой_текст}
    исторические_пути: set[str] = set()
    for идентификатор, тема in темы.items():
        путь = тема.get("путь")
        if not isinstance(путь, str):
            raise ОшибкаПроверки(f"тема {идентификатор}: путь отсутствует")
        if путь in пути_тем:
            raise ОшибкаПроверки(f"тема {идентификатор}: путь {путь!r} повторён")
        файл = проверить_точный_локальный_путь(корень, путь)
        текст = файл.read_text(encoding="utf-8")
        ожидаемый_хэш = тема.get("sha256_содержания")
        if ШАБЛОН_ХЭША.fullmatch(str(ожидаемый_хэш)) is None:
            raise ОшибкаПроверки(f"тема {идентификатор}: хэш содержания некорректен")
        if хэш_содержания_разметки(текст) != ожидаемый_хэш:
            raise ОшибкаПроверки(f"тема {идентификатор}: хэш содержания не совпадает")
        полномочия = тема.get("полномочия")
        if not isinstance(полномочия, bool):
            raise ОшибкаПроверки(f"тема {идентификатор}: полномочия должны быть bool")
        if not полномочия:
            исторические_пути.add(путь)
        пути_тем[путь] = тема
        тексты[путь] = текст

    служебные_пути = манифест.get("служебные_пути_изменения_правил", [])
    if not isinstance(служебные_пути, list) or any(
        not isinstance(путь, str) for путь in служебные_пути
    ):
        raise ОшибкаПроверки("служебные пути изменения правил должны быть массивом строк")
    for путь in служебные_пути:
        проверить_точный_локальный_путь(корень, путь)

    маршруты = индексировать_по_идентификатору(
        потребовать_список(манифест, "маршруты"), "маршруты"
    )
    карта_маршрутов: dict[str, list[str]] = {}
    допустимые_пути = set(пути_тем) | set(служебные_пути)
    for идентификатор, маршрут in маршруты.items():
        пути = маршрут.get("пути")
        if not isinstance(пути, list) or any(not isinstance(путь, str) for путь in пути):
            raise ОшибкаПроверки(f"маршрут {идентификатор}: пути должны быть массивом строк")
        if len(пути) != len(set(пути)):
            raise ОшибкаПроверки(f"маршрут {идентификатор}: путь повторён")
        неизвестные = set(пути) - допустимые_пути
        if неизвестные:
            raise ОшибкаПроверки(
                f"маршрут {идентификатор}: неизвестный путь {sorted(неизвестные)[0]!r}"
            )
        if идентификатор != "правила" and исторические_пути.intersection(пути):
            raise ОшибкаПроверки(f"маршрут {идентификатор}: исторический файл не даёт полномочий")
        карта_маршрутов[идентификатор] = пути
    ожидаемый_маршрут_правил = set(пути_тем) | set(служебные_пути)
    if set(карта_маршрутов.get("правила", [])) != ожидаемый_маршрут_правил:
        raise ОшибкаПроверки(
            "маршрут «изменение правил» не охватывает весь набор тем и инвентарь"
        )
    корневые_маршруты = разобрать_корневые_маршруты(корневой_текст)
    if {ключ: set(пути) for ключ, пути in корневые_маршруты.items()} != {
        ключ: set(пути) for ключ, пути in карта_маршрутов.items()
    }:
        raise ОшибкаПроверки("корневой маршрут не согласован с машинным инвентарём")

    снимок = манифест.get("исходный_снимок")
    исходные_байты = прочитать_исходный_снимок(корень, снимок)
    исходные = проверить_исходные_единицы(
        потребовать_список(манифест, "исходные_единицы"),
        исходные_байты,
        снимок["байтов"],
    )
    правила = индексировать_по_идентификатору(
        потребовать_список(манифест, "правила"), "правила"
    )
    использованные_источники: list[str] = []
    активные_ключи: set[str] = set()
    активные_назначения: set[tuple[str, str]] = set()
    for идентификатор, правило in правила.items():
        статус = правило.get("статус")
        приоритет = правило.get("приоритет")
        области = правило.get("области")
        триггеры = правило.get("триггеры")
        ключ = правило.get("семантический_ключ")
        назначение = правило.get("назначение")
        источники = правило.get("источники")
        новое_основание = правило.get("новое_основание")
        if статус not in (
            "действует",
            "история",
            "исчерпано",
            "контекст",
            "происхождение",
        ):
            raise ОшибкаПроверки(f"правило {идентификатор}: статус неизвестен")
        if not isinstance(приоритет, str) or not приоритет:
            raise ОшибкаПроверки(f"правило {идентификатор}: приоритет отсутствует")
        if not isinstance(области, list) or not области:
            raise ОшибкаПроверки(f"правило {идентификатор}: области отсутствуют")
        if not isinstance(триггеры, list) or not триггеры:
            raise ОшибкаПроверки(f"правило {идентификатор}: триггеры отсутствуют")
        if not isinstance(ключ, str) or not ключ:
            raise ОшибкаПроверки(f"правило {идентификатор}: семантический ключ отсутствует")
        if not isinstance(назначение, dict):
            raise ОшибкаПроверки(f"правило {идентификатор}: назначение отсутствует")
        путь = назначение.get("путь")
        якорь = назначение.get("якорь")
        if путь not in тексты or not isinstance(якорь, str) or not якорь:
            raise ОшибкаПроверки(f"правило {идентификатор}: назначение некорректно")
        метка = ШАБЛОН_МЕТКИ_ПРАВИЛА.format(идентификатор=якорь)
        if тексты[путь].count(метка) != 1 or якорь != идентификатор:
            raise ОшибкаПроверки(f"правило {идентификатор}: назначение или якорь не уникальны")
        if not isinstance(источники, list):
            raise ОшибкаПроверки(f"правило {идентификатор}: источники должны быть массивом")
        if not источники:
            if not isinstance(новое_основание, str) or not новое_основание:
                raise ОшибкаПроверки(
                    f"правило {идентификатор}: исходный инвентарь не покрыт и новое основание отсутствует"
                )
            проверить_точный_локальный_путь(корень, новое_основание)
        if any(источник not in исходные for источник in источники):
            raise ОшибкаПроверки(f"правило {идентификатор}: неизвестный исходный идентификатор")
        if any(
            исходные[источник].get("требует_правило", True) is not True
            for источник in источники
        ):
            raise ОшибкаПроверки(
                f"правило {идентификатор}: ссылается на ненормативную исходную единицу"
            )
        использованные_источники.extend(источники)
        if статус == "действует":
            if ключ in активные_ключи:
                raise ОшибкаПроверки(
                    f"правило {идентификатор}: семантический ключ активного правила повторён"
                )
            активные_ключи.add(ключ)
            пара = (путь, якорь)
            if пара in активные_назначения:
                raise ОшибкаПроверки(
                    f"правило {идентификатор}: назначение активного правила повторено"
                )
            активные_назначения.add(пара)
        elif путь in пути_тем and пути_тем[путь].get("полномочия") is not False:
            if статус in ("история", "исчерпано", "происхождение"):
                raise ОшибкаПроверки(
                    f"правило {идентификатор}: исторический статус размещён в активной теме"
                )

    счётчик = Counter(использованные_источники)
    обязательные_источники = {
        идентификатор
        for идентификатор, элемент in исходные.items()
        if элемент.get("требует_правило", True) is True
    }
    непокрытые = обязательные_источники - set(счётчик)
    лишние = set(счётчик) - обязательные_источники
    повторённые = sorted(
        идентификатор for идентификатор, число in счётчик.items() if число != 1
    )
    if непокрытые or лишние or повторённые:
        raise ОшибкаПроверки(
            "исходный инвентарь покрыт неполно или неоднозначно: "
            f"непокрытых={len(непокрытые)}, лишних={len(лишние)}, "
            f"повторённых={len(повторённые)}"
        )

    фикстуры = потребовать_список(манифест, "фикстуры_маршрутизации")
    for номер, фикстура in enumerate(фикстуры):
        if not isinstance(фикстура, dict):
            raise ОшибкаПроверки(f"фикстура маршрутизации {номер} должна быть объектом")
        триггеры = фикстура.get("триггеры")
        ожидаемые = фикстура.get("ожидаемые_пути")
        if (
            not isinstance(триггеры, list)
            or not триггеры
            or not isinstance(ожидаемые, list)
        ):
            raise ОшибкаПроверки(f"фикстура маршрутизации {номер} некорректна")
        неизвестные = set(триггеры) - set(карта_маршрутов)
        if неизвестные:
            raise ОшибкаПроверки(f"фикстура маршрутизации {номер}: неизвестный триггер")
        фактические = set().union(
            *(set(карта_маршрутов[триггер]) for триггер in триггеры)
        )
        if фактические != set(ожидаемые):
            raise ОшибкаПроверки(
                f"фикстура маршрутизации {номер}: безопасное объединение не совпадает"
            )

    return карта_маршрутов, sorted(пути_тем)


def разобрать_аргументы(аргументы: Sequence[str] | None = None) -> argparse.Namespace:
    разбор = argparse.ArgumentParser(description="Проверить декомпозицию правил агентов FUM.")
    разбор.add_argument("--корень-репозитория", type=Path, default=Path.cwd())
    разбор.add_argument(
        "--инвентарь",
        default="Правила/агентов/инвентарь-правил.json",
    )
    команды = разбор.add_subparsers(dest="команда", required=True)
    команды.add_parser("проверить")
    маршрут = команды.add_parser("маршрут")
    маршрут.add_argument("--триггер", action="append", required=True)
    return разбор.parse_args(аргументы)


def главная(аргументы: Sequence[str] | None = None) -> int:
    параметры = разобрать_аргументы(аргументы)
    корень = параметры.корень_репозитория.resolve()
    try:
        путь_инвентаря = проверить_точный_локальный_путь(
            корень,
            параметры.инвентарь,
        )
        манифест = прочитать_инвентарь(путь_инвентаря)
        маршруты, темы = проверить_структуру(корень, манифест)
        if параметры.команда == "маршрут":
            неизвестные = sorted(set(параметры.триггер) - set(маршруты))
            if неизвестные:
                raise ОшибкаПроверки(
                    f"неизвестный триггер маршрута: {неизвестные[0]}"
                )
            пути = sorted(
                set().union(
                    *(set(маршруты[триггер]) for триггер in параметры.триггер)
                )
            )
            print(
                json.dumps(
                    {"схема": "fum.маршрут-правил-агентов.1", "пути": пути},
                    ensure_ascii=False,
                    sort_keys=True,
                )
            )
        else:
            print(f"Проверено правил: {len(манифест['правила'])}; тем: {len(темы)}")
        return 0
    except (ОшибкаПроверки, UnicodeDecodeError) as ошибка:
        print(f"Ошибка: {ошибка}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(главная())

"""Конечные собственные аббревиатуры формата не открывают соседние имена."""

import hashlib
import importlib.util
import json
from pathlib import Path
import sys
import tempfile
import unittest

путь = Path(__file__).resolve().parents[1] / "scripts" / "перевести-объявления-кода.py"
спецификация = importlib.util.spec_from_file_location("учёт_аббревиатур", путь)
учёт = importlib.util.module_from_spec(спецификация)
sys.modules[спецификация.name] = учёт
спецификация.loader.exec_module(учёт)
import аббревиатуры_контекста as перечень
путь_поддержки = "Проекты/рабочий-контекст/общие/Python/поддержка_моделей.py"


class ПроверкиАббревиатурКонтекста(unittest.TestCase):
    def инвентарь(сам, путь_файла, текст):
        with tempfile.TemporaryDirectory() as папка:
            корень = Path(папка)
            файл = корень / путь_файла
            файл.parent.mkdir(parents=True, exist_ok=True)
            файл.write_text(текст, encoding="utf-8")
            return учёт.построить_инвентарь(корень)["объявления"]

    def test_точное_имя_формата_разрешено(сам):
        сам.assertEqual([], сам.инвентарь(путь_поддержки, "def проверить_JSON(значение): return значение\n"))

    def test_соседний_путь_имя_и_вид_не_разрешены(сам):
        for путь_файла, текст, имя in [
            ("сосед.py", "def проверить_JSON(): pass\n", "проверить_JSON"),
            (путь_поддержки, "def подменить_JSON(): pass\n", "подменить_JSON"),
            (путь_поддержки, "проверить_JSON = 1\n", "проверить_JSON"),
            (путь_поддержки, "def JSON(): pass\n", "JSON"),
        ]:
            with сам.subTest(путь=путь_файла, текст=текст):
                сам.assertIn(имя, {з["имя"] for з in сам.инвентарь(путь_файла, текст)})

    def test_составные_типы_свифт_имеют_точную_область(сам):
        путь_свифт = "Проекты/рабочий-контекст/общие/Swift/ПоддержкаJSON.swift"
        текст = "struct ЗначениеJSON {}\nstruct ПолеJSON {}\nstruct СтрогийРазборJSON {}\nfunc разобратьJSON() {}\n"
        сам.assertEqual([], сам.инвентарь(путь_свифт, текст))
        сам.assertEqual(4, len(сам.инвентарь("сосед.swift", текст)))

    def test_разрешённое_собственное_имя_остаётся_доступно_карте(сам):
        with tempfile.TemporaryDirectory() as папка:
            корень = Path(папка)
            файл = корень / путь_поддержки
            файл.parent.mkdir(parents=True)
            файл.write_text("def проверить_JSON(значение): return значение\n", encoding="utf-8")
            запись = учёт.ЗаписьКарты(путь_поддержки, "sha256:" + hashlib.sha256(файл.read_bytes()).hexdigest(),
                                      {"проверить_JSON": "проверить_представление"})
            изменения = учёт.подготовить_изменения(корень, [запись])
            сам.assertIn("def проверить_представление", изменения[0].новый_текст)

    def test_канонический_набор_содержит_ровно_восемь_точных_исключений(сам):
        префикс = "Проекты/рабочий-контекст/"
        ожидаемые = {
            (префикс + "общие/Python/поддержка_моделей.py", "python", "функция", имя)
            for имя in ("проверить_JSON", "разобрать_JSON")
        } | {
            (префикс + "порождённые/модели_ответа.py", "python", "функция", имя)
            for имя in ("из_JSON", "в_JSON")
        } | {
            (префикс + "общие/Swift/ПоддержкаJSON.swift", "swift", "тип", имя)
            for имя in ("ЗначениеJSON", "ПолеJSON", "СтрогийРазборJSON")
        } | {(префикс + "общие/Swift/ПоддержкаJSON.swift", "swift", "функция", "разобратьJSON")}
        сам.assertEqual(ожидаемые, перечень.прочитать_перечень())

    def test_повреждённая_и_расширенная_структура_закрывается(сам):
        исходный = json.loads(перечень.путь_перечня.read_text())
        варианты = []
        варианты.append({**исходный, "неизвестное": True})
        варианты.append({**исходный, "схема": "неизвестная"})
        варианты.append({**исходный, "исключения": []})
        варианты.append({**исходный, "исключения": исходный["исключения"] * 2})
        for поле, значение in [("путь", "Проекты/сосед/код.py"), ("язык", "mermaid"),
                              ("вид", "свойство"), ("имя", "JSON"), ("имя", "прочитать_*JSON"),
                              ("класс", "внешний-api"), ("причина", ""),
                              ("источник", "git:HEAD:файл.py"), ("хэш_источника", "sha256:00"),
                              ("неизвестное", "значение")]:
            данные = json.loads(json.dumps(исходный))
            данные["исключения"][0][поле] = значение
            if поле == "путь":
                прежний_источник = данные["исключения"][0]["источник"]
                данные["исключения"][0]["источник"] = прежний_источник.rsplit(":", 1)[0] + ":" + значение
            варианты.append(данные)
        with tempfile.TemporaryDirectory() as папка:
            файл = Path(папка).resolve() / "перечень.json"
            for данные in варианты:
                with сам.subTest(данные=данные):
                    файл.write_text(json.dumps(данные))
                    with сам.assertRaises(ValueError):
                        перечень.прочитать_перечень(файл)
            for текст in ['{', '{"схема":1,"схема":2,"исключения":[]}']:
                файл.write_text(текст)
                with сам.assertRaises(ValueError):
                    перечень.прочитать_перечень(файл)

    def test_ссылка_на_перечень_не_разрешает_исключения(сам):
        with tempfile.TemporaryDirectory() as папка:
            ссылка = Path(папка).resolve() / "ссылка.json"
            ссылка.symlink_to(перечень.путь_перечня)
            with сам.assertRaises(перечень.ОшибкаПеречня):
                перечень.прочитать_перечень(ссылка)


if __name__ == "__main__":
    unittest.main()

"""Открытые примеры конечного шаблона; произвольный JavaScript не поддержан."""
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


путь_скрипта = Path(__file__).resolve().parents[1] / "scripts/перевести-объявления-кода.py"
описание_модуля = importlib.util.spec_from_file_location("перевод_для_адаптера", путь_скрипта)
модуль = importlib.util.module_from_spec(описание_модуля)
sys.modules[описание_модуля.name] = модуль
описание_модуля.loader.exec_module(модуль)
путь_адаптера = "Инструменты/fum-reyestr-planirovaniya/scripts/адаптер-codex.js"


def образец(возможности="возможности", вход="вход", допуск="допуск", ответ="ответ"):
    return (
        f"async ({возможности}, {вход}) => {{\n"
        f"  const {допуск} = await {возможности}.подготовить({вход});\n"
        f"  if ({допуск}.разрешён_вызов) {{\n"
        f"    const {ответ} = await {возможности}.исполнить({допуск});\n"
        f"    return await {возможности}.сохранить({допуск}, {ответ});\n"
        "  }\n"
        f"  return {допуск};\n"
        "}\n"
    )


class ПроверкаШаблонаАдаптера(unittest.TestCase):
    def разобрать(сам, текст):
        return модуль.объявления_адаптера(текст, путь_адаптера)

    def инвентарь(сам, файлы):
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный)
            for путь, текст in файлы.items():
                файл = корень / путь
                файл.parent.mkdir(parents=True, exist_ok=True)
                файл.write_text(текст, encoding="utf-8")
            return модуль.построить_инвентарь(корень)

    def test_кириллица_даёт_нулевой_остаток(сам):
        сам.assertEqual(сам.разобрать(образец()), [])
        сам.assertEqual(сам.инвентарь({путь_адаптера: образец()}),
                        {"версия_схемы": 1, "объявления": []})

    def test_все_четыре_латинские_привязки_имеют_точное_происхождение(сам):
        текст = образец("capabilities", "input", "permit", "reply")
        записи = [запись.словарь() for запись in сам.разобрать(текст)]
        сам.assertEqual([(з["имя"], з["вид"], з["строка"], з["столбец"]) for з in записи],
                        [("capabilities", "параметр", 1, 8), ("input", "параметр", 1, 22),
                         ("permit", "привязка", 2, 9), ("reply", "привязка", 4, 11)])
        сам.assertTrue(all(з["язык"] == "javascript" and з["путь"] == путь_адаптера for з in записи))

    def test_пробелы_и_разрешённые_переводы_строк(сам):
        текст = образец().replace("  ", "\t").replace("\n", "\r\n")
        сам.assertEqual(сам.разобрать(текст), [])
        записи = сам.разобрать(образец("capabilities").replace("\n", "\r"))
        сам.assertEqual(записи[0].строка, 1)

    def test_самостоятельный_перевод_яваскрипта_отказывает(сам):
        for расширение in ("js", "mjs", "cjs"):
            with сам.subTest(расширение=расширение):
                with сам.assertRaises(модуль.ОшибкаКонтракта):
                    модуль.нормализовать_путь("Инструменты/пример." + расширение)

    def test_сходные_пути_не_расширяют_допуск(сам):
        for путь in ("пример.js", путь_адаптера + ".js", путь_адаптера.replace(".js", ".mjs"),
                     путь_адаптера.replace(".js", ".cjs"), путь_адаптера.replace(".js", ".JS"),
                     путь_адаптера.replace("Инструменты/", "инструменты/")):
            with сам.subTest(путь=путь):
                with сам.assertRaises(модуль.ОшибкаКонтракта):
                    сам.инвентарь({путь: образец()})

    def test_проекция_исключена_только_в_точном_корне(сам):
        сам.assertEqual(сам.инвентарь({"Proyekcii/копия.js": "не код"})["объявления"], [])
        for путь in ("Proyekcii-copy/копия.js", "Документация/Proyekcii/копия.js"):
            with сам.subTest(путь=путь), сам.assertRaises(модуль.ОшибкаКонтракта):
                сам.инвентарь({путь: образец()})

    def test_самостоятельный_блок_яваскрипта_отказывает_а_дословный_защищён(сам):
        for язык in ("js", "javascript", "mjs", "cjs"):
            текст = "# Пример\n\n```" + язык + "\n" + образец() + "```\n"
            with сам.subTest(язык=язык), сам.assertRaises(модуль.ОшибкаКонтракта):
                сам.инвентарь({"Документация/пример.md": текст})
            защищённый = "# Запрос\n\n## Текст запроса\n\n" + текст
            сам.assertEqual(сам.инвентарь({"Журнал/2026-01-01_00-00-00_MSK_пример/запрос.md": защищённый})["объявления"], [])

    def test_другая_ссылка_на_привязку_отказывает(сам):
        for прежнее, новое in (("подготовить(вход)", "подготовить(чужой)"),
                               ("исполнить(допуск)", "исполнить(вход)"),
                               ("сохранить(допуск, ответ)", "сохранить(ответ, допуск)"),
                               ("return допуск;", "return вход;")):
            with сам.subTest(замена=прежнее), сам.assertRaises(модуль.ОшибкаКонтракта):
                сам.разобрать(образец().replace(прежнее, новое))

    def test_совпадение_имён_и_ключевые_слова_отказывают(сам):
        for имена in (("вход", "вход", "допуск", "ответ"),
                      ("возможности", "вход", "вход", "ответ"),
                      ("возможности", "вход", "допуск", "допуск"),
                      ("await", "вход", "допуск", "ответ"),
                      ("возможности", "вход", "return", "ответ"),
                      ("eval", "вход", "допуск", "ответ")):
            with сам.subTest(имена=имена), сам.assertRaises(модуль.ОшибкаКонтракта):
                сам.разобрать(образец(*имена))

    def test_опасные_разрывы_строк_отказывают(сам):
        for прежнее, новое in (("async (", "async\n("), ("=>", "\n=>"),
                               ("return await", "return\nawait"),
                               ("return допуск", "return\rдопуск")):
            with сам.subTest(замена=прежнее), сам.assertRaises(модуль.ОшибкаКонтракта):
                сам.разобрать(образец().replace(прежнее, новое))

    def test_комментарии_строки_экранирование_и_лишние_конструкции_отказывают(сам):
        исходный = образец()
        варианты = [
            "// комментарий\n" + исходный, исходный + "; alert(1)", исходный + "/* хвост */",
            исходный + исходный, исходный.replace("вход", "\\u0061"),
            исходный.replace("const допуск", "let допуск"),
            исходный.replace("const допуск", "const {допуск}"),
            исходный.replace("подготовить(вход)", "подготовить('вход')"),
            исходный.replace("подготовить(вход)", "подготовить(() => вход)"),
            исходный.replace("return допуск;", "допуск.чужое = вход; return допуск;"),
            исходный.replace("return допуск;", "return допуск")]
        for номер, текст in enumerate(варианты):
            with сам.subTest(номер=номер), сам.assertRaises(модуль.ОшибкаКонтракта):
                сам.разобрать(текст)

    def test_кириллица_латиница_и_юникод_независимо_проверены_интерпретатором(сам):
        интерпретатор = shutil.which("node")
        сам.assertIsNotNone(интерпретатор, "Для независимой проверки нужен объявленный Node.js в PATH")
        окружение = {ключ: значение for ключ, значение in os.environ.items()
                     if ключ not in {"NODE_OPTIONS", "NODE_PATH"}}
        for имена in (("возможности", "вход", "допуск", "ответ"),
                      ("capabilities", "input", "permit", "reply"),
                      ("$возможности", "вход_δ", "допуск١", "отве́т")):
            текст = образец(*имена)
            with сам.subTest(имена=имена):
                сам.разобрать(текст)
                результат = subprocess.run([интерпретатор, "--check", "--input-type=module"],
                                            input=текст, text=True, capture_output=True,
                                            env=окружение, timeout=10)
                сам.assertEqual(результат.returncode, 0, результат.stderr)

    def test_слишком_большой_ввод_отказывает(сам):
        with сам.assertRaises(модуль.ОшибкаКонтракта):
            сам.разобрать(" " * 65537 + образец())

    def test_контекстное_имя_не_становится_ключевым_словом(сам):
        текст = образец("async").replace("async.сохранить", "async\n      .сохранить")
        сам.assertEqual([з.имя for з in сам.разобрать(текст)], ["async"])
        результат = subprocess.run([shutil.which("node"), "--check", "--input-type=module"],
                                    input=текст, text=True, capture_output=True, timeout=10,
                                    env={ключ: значение for ключ, значение in os.environ.items()
                                         if ключ not in {"NODE_OPTIONS", "NODE_PATH"}})
        сам.assertEqual(результат.returncode, 0, результат.stderr)

    def test_питон_исключения_не_скрывают_латинские_имена_яваскрипта(сам):
        сам.assertEqual([з.имя for з in сам.разобрать(образец("__foreign__", "test_вход"))],
                        ["__foreign__", "test_вход"])

    def test_символическая_ссылка_предка_не_скрывает_точный_адаптер(сам):
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный) / "checkout"
            корень.mkdir()
            внешнее = Path(временный) / "внешнее"
            файл = внешнее / "fum-reyestr-planirovaniya/scripts/адаптер-codex.js"
            файл.parent.mkdir(parents=True)
            файл.write_text(образец(), encoding="utf-8")
            (корень / "Инструменты").symlink_to(внешнее, target_is_directory=True)
            with сам.assertRaises(модуль.ОшибкаКонтракта):
                модуль.построить_инвентарь(корень)

    def test_ограды_в_контейнерах_не_скрывают_яваскрипт(сам):
        for префикс in ("    ", "> ", "  > > ", "- ", "1. "):
            текст = "# Пример\n\n" + префикс + "```javascript\n" + образец() + префикс + "```\n"
            with сам.subTest(префикс=префикс), сам.assertRaises(модуль.ОшибкаКонтракта):
                сам.инвентарь({"Документация/пример.md": текст})
            сам.assertEqual(сам.инвентарь({"Журнал/2026-01-01_00-00-00_MSK_пример/запрос.md":
                                          "# Запрос\n\n## Текст запроса\n\n" + текст})["объявления"], [])


if __name__ == "__main__":
    unittest.main()

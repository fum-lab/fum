#!/usr/bin/env python3
"""Согласованно перевести три имени в четырёх точных исходниках контекста."""

import argparse
import importlib.util
from pathlib import Path
import sys

спецификация = importlib.util.spec_from_file_location("перевод_контекста_ядро", Path(__file__).with_name("перевести-объявления-кода.py"))
учёт = importlib.util.module_from_spec(спецификация)
sys.modules[спецификация.name] = учёт
спецификация.loader.exec_module(учёт)

путь_контракта = "Прототипы/память-структурирующих-операторов/Sources/FUMStructuringOperatorMemory/СтруктурныйКонтракт.swift"
путь_поддержки = "Проекты/рабочий-контекст/общие/Swift/ПоддержкаМоделей.swift"
путь_генератора = "Прототипы/память-структурирующих-операторов/Sources/FUMStructuringOperatorMemory/ПорождениеМоделей.swift"
путь_проверки = "Проекты/рабочий-контекст/проверки/ПроверкиОпераций.swift"
старый_шаблон = '"private let описаниеМоделей = try! КонтрактМоделей(base64: ["'
новый_шаблон = '"private let описаниеМоделей = try! КонтрактМоделей(кодированноеОписание: ["'
пути = frozenset({путь_контракта, путь_поддержки, путь_генератора, путь_проверки})


def подготовить(корень, манифест):
    if not isinstance(манифест, dict) or set(манифест) != {"схема", "файлы"}:
        raise учёт.ОшибкаКонтракта("неверные поля миграции контекста")
    хэши = манифест["файлы"]
    if манифест["схема"] != "fum.миграция-имён-контекста.1" or not isinstance(хэши, dict) or set(хэши) != пути:
        raise учёт.ОшибкаКонтракта("миграция требует все четыре точных исходника")
    корень = Path(корень).resolve()
    тексты = {}
    for путь, ожидаемый in хэши.items():
        if not isinstance(ожидаемый, str) or учёт.шаблон_хэша.fullmatch(ожидаемый) is None:
            raise учёт.ОшибкаКонтракта("неверный хэш миграции")
        файл = корень
        for часть in Path(путь).parts:
            файл /= часть
            if файл.is_symlink():
                raise учёт.ОшибкаКонтракта("ссылка в пути миграции")
        байты = файл.read_bytes()
        if учёт.вычислить_хэш(байты) != ожидаемый:
            raise учёт.ОшибкаКонтракта("дрейф исходника миграции: " + путь)
        тексты[путь] = байты.decode("utf-8")
    записи = [
        учёт.ЗаписьКарты(путь_контракта, хэши[путь_контракта],
                         {"допускаетNull": "допускаетПустойМаркер", "null": "допускПустогоМаркера"}),
        учёт.ЗаписьКарты(путь_поддержки, хэши[путь_поддержки], {"base64": "кодированноеОписание"}),
    ]
    изменения = учёт.подготовить_изменения(корень, записи)
    for путь in (путь_генератора, путь_проверки):
        текст = тексты[путь]
        токены = учёт.токены_свифт(текст, со_строками=True)
        замены = []
        for номер, токен in enumerate(токены):
            if путь == путь_генератора and токен.вид == "идентификатор" and токен.текст == "допускаетNull":
                if [т.текст for т in токены[max(0, номер - 2):номер]] != ["поле", "."]:
                    raise учёт.ОшибкаКонтракта("неподтверждённый владелец ссылки поля")
                замены.append((токен.начало, токен.конец, "допускаетПустойМаркер", "допускаетNull"))
            if путь == путь_генератора and токен.вид == "строка" and токен.текст == старый_шаблон:
                if номер and токены[номер - 1].текст == "#":
                    raise учёт.ОшибкаКонтракта("сырой шаблон не поддержан")
                замены.append((токен.начало, токен.конец, новый_шаблон, "шаблон-конструктора"))
            if путь == путь_проверки and токен.вид == "идентификатор" and токен.текст == "base64":
                if ([т.текст for т in токены[max(0, номер - 2):номер]] != ["КонтрактМоделей", "("]
                        or номер + 1 >= len(токены) or токены[номер + 1].текст != ":"):
                    raise учёт.ОшибкаКонтракта("неподтверждённая роль метки конструктора")
                замены.append((токен.начало, токен.конец, "кодированноеОписание", "base64"))
        количества = {имя: sum(з[3] == имя for з in замены) for имя in {з[3] for з in замены}}
        ожидаемые = {"допускаетNull": 4, "шаблон-конструктора": 1} if путь == путь_генератора else {"base64": 1}
        if количества != ожидаемые:
            raise учёт.ОшибкаКонтракта("неверное число ссылок или шаблонов: " + путь)
        новые = {"допускаетПустойМаркер", "кодированноеОписание"}
        if any(т.вид == "идентификатор" and т.текст in новые for т in токены):
            raise учёт.ОшибкаКонтракта("коллизия нового имени ссылочного файла")
        результат = учёт.применить_замены(текст, замены)
        изменения.append(учёт.ИзменениеФайла(
            путь, корень / путь, результат, хэши[путь], учёт.вычислить_хэш(результат.encode("utf-8")),
            {имя: новое for _, _, новое, имя in замены}, количества))
    return sorted(изменения, key=lambda изменение: изменение.путь)


def главная():
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument("действие", choices=("план", "применить"))
    разборщик.add_argument("--корень-репозитория", type=Path, required=True)
    разборщик.add_argument("--вход", type=Path, required=True)
    параметры = разборщик.parse_args()
    try:
        изменения = подготовить(параметры.корень_репозитория, учёт.прочитать_данные(параметры.вход))
        if параметры.действие == "применить":
            учёт.атомарно_применить(изменения)
        print(учёт.канонический_текст(учёт.описание_плана(изменения, параметры.действие)))
        return 0
    except (учёт.ОшибкаКонтракта, OSError, UnicodeError) as ошибка:
        print("ошибка: " + str(ошибка), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(главная())

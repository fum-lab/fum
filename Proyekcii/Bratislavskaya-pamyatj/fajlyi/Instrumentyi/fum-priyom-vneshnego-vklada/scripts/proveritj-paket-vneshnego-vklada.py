def _закрытый_объект(значение: Any, имя: str, обязательные: set[str]) -> dict[str, Any]:
    if not isinstance(значение, dict):
        raise ОшибкаКонтракта(f"{имя}: ожидается JSON-объект")
    фактические = set(значение)
    отсутствующие = sorted(обязательные - фактические)
    неизвестные = sorted(фактические - обязательные)
    if отсутствующие:
        raise ОшибкаКонтракта(f"{имя}: отсутствуют поля: {', '.join(отсутствующие)}")
    if неизвестные:
        raise ОшибкаКонтракта(f"{имя}: неизвестные поля: {', '.join(неизвестные)}")
    return значение


def _непустая_строка(значение: Any, имя: str) -> str:
    if (
        not isinstance(значение, str)
        or not значение.strip()
        or значение != значение.strip()
        or len(значение) > МАКСИМУМ_СИМВОЛОВ_СТРОКИ
    ):
        raise ОшибкаКонтракта(f"{имя}: ожидается непустая строка без краевых пробелов")
    if unicodedata.normalize("NFC", значение) != значение:
        raise ОшибкаКонтракта(f"{имя}: требуется Unicode NFC")
    if any(unicodedata.category(символ) in {"Cc", "Cf", "Cs"} for символ in значение):
        raise ОшибкаКонтракта(f"{имя}: управляющие, format- и surrogate-символы запрещены")
    return значение


def _список_строк(значение: Any, имя: str) -> list[str]:
    if not isinstance(значение, list) or not значение or len(значение) > МАКСИМУМ_ЭЛЕМЕНТОВ_СПИСКА:
        raise ОшибкаКонтракта(f"{имя}: ожидается непустой массив")
    return [_непустая_строка(элемент, f"{имя}[{индекс}]") for индекс, элемент in enumerate(значение)]


def _объект_без_повторов(пары: list[tuple[str, Any]]) -> dict[str, Any]:
    результат: dict[str, Any] = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ОшибкаКонтракта(f"JSON: повтор поля {ключ!r}")
        результат[ключ] = значение
    return результат


def загрузить_байты_джейсон(данные: bytes, имя: str) -> dict[str, Any]:
    try:
        текст = данные.decode("utf-8")
    except UnicodeDecodeError as error:
        raise ОшибкаКонтракта(f"{имя}: ожидается UTF-8: {error}") from error
    try:
        значение = json.loads(текст, object_pairs_hook=_объект_без_повторов)
    except (json.JSONDecodeError, ОшибкаКонтракта) as error:
        raise ОшибкаКонтракта(f"{имя}: некорректный JSON: {error}") from error
    if not isinstance(значение, dict):
        raise ОшибкаКонтракта(f"{имя}: корень должен быть объектом")
    return значение


def прочитать_ограниченный_файл(путь: Path, максимум_байтов: int, имя: str) -> bytes:
    with путь.open("rb") as поток:
        размер = os.fstat(поток.fileno()).st_size
        if размер > максимум_байтов:
            raise ОшибкаКонтракта(f"{имя}: размер {размер} превышает лимит {максимум_байтов} байт")
        данные = поток.read(максимум_байтов + 1)
    if len(данные) > максимум_байтов:
        raise ОшибкаКонтракта(f"{имя}: превышен лимит {максимум_байтов} байт")
    return данные


def отклонить_известные_секреты(данные: bytes, имя: str) -> None:
    for шаблон in ШАБЛОНЫ_СЕКРЕТОВ:
        if шаблон.search(данные):
            raise ОшибкаКонтракта(f"{имя}: обнаружена известная сигнатура секрета")


def чистая_среда_системы_версий() -> dict[str, str]:
    среда = {
        ключ: значение
        for ключ, значение in os.environ.items()
        if not ключ.startswith("GIT_")
    }
    среда["GIT_NO_REPLACE_OBJECTS"] = "1"
    среда["GIT_OPTIONAL_LOCKS"] = "0"
    return среда


def ограничить_ресурсы_системы_версий() -> None:
    ограничения = (
        (resource.RLIMIT_FSIZE, МАКСИМУМ_РАЗМЕРА_ФАЙЛА_СИСТЕМЫ_ВЕРСИЙ),
        (resource.RLIMIT_CPU, ТАЙМ_АУТ_СИСТЕМЫ_ВЕРСИЙ_В_СЕКУНДАХ),
        (resource.RLIMIT_CORE, 0),
    )
    for ресурс, предел in ограничения:
        _мягкий, жёсткий = resource.getrlimit(ресурс)
        новый_мягкий = предел if жёсткий == resource.RLIM_INFINITY else min(предел, жёсткий)
        try:
            resource.setrlimit(ресурс, (новый_мягкий, жёсткий))
        except ValueError:
            resource.setrlimit(ресурс, (новый_мягкий, новый_мягкий))


def нормализованный_ключ_пути(путь: str) -> tuple[str, ...]:
    return tuple(unicodedata.normalize("NFC", часть).casefold() for часть in PurePosixPath(путь).parts)


def _проверить_путь(сырой_путь: Any) -> str:
    путь = _непустая_строка(сырой_путь, "манифест.путь")
    if len(путь) > МАКСИМУМ_СИМВОЛОВ_ПУТИ:
        raise ОшибкаКонтракта(f"манифест.путь {путь!r}: превышен лимит {МАКСИМУМ_СИМВОЛОВ_ПУТИ} символов")
    if (
        any(символ.isspace() for символ in путь)
        or "\\" in путь
        or '"' in путь
        or any(символ in путь for символ in "*?[]:")
    ):
        raise ОшибкаКонтракта(f"манифест.путь {путь!r}: пробелы, кавычка и обратная косая черта запрещены")
    чистый_путь = PurePosixPath(путь)
    if (
        чистый_путь.is_absolute()
        or путь.startswith("/")
        or путь != чистый_путь.as_posix()
        or any(часть in {"", ".", ".."} for часть in чистый_путь.parts)
    ):
        raise ОшибкаКонтракта(f"манифест.путь {путь!r}: небезопасный относительный путь")
    if len(чистый_путь.parts) > МАКСИМУМ_КОМПОНЕНТОВ_ПУТИ:
        raise ОшибкаКонтракта(f"манифест.путь {путь!r}: превышена глубина {МАКСИМУМ_КОМПОНЕНТОВ_ПУТИ}")
    безрегистровый_путь = путь.casefold()
    безрегистровые_части = tuple(часть.casefold() for часть in чистый_путь.parts)
    первый_компонент = безрегистровые_части[0]
    if (
        any(часть.startswith(".git") or часть in {".codex", ".obsidian"} for часть in безрегистровые_части)
        or безрегистровые_части[-1] == "agents.md"
        or безрегистровый_путь in {элемент.casefold() for элемент in ТОЧНЫЕ_ЗАЩИЩЁННЫЕ_ПУТИ}
        or any(
        безрегистровый_путь.startswith(префикс.casefold()) for префикс in ЗАЩИЩЁННЫЕ_ПРЕФИКСЫ
        )
    ):
        raise ОшибкаКонтракта(f"манифест.путь {путь!r}: запрещённая управляющая или производная область")
    return путь


def проверить_форму_пакета(внешний_пакет: dict[str, Any]) -> tuple[list[dict[str, str]], bytes]:
    обязательные = {
        "схема",
        "идентификатор_предложения",
        "репозиторий",
        "утверждение",
        "критерии_приёмки",
        "манифест",
        "патч",
        "заявленные_проверки",
        "ограничения",
    }
    _закрытый_объект(внешний_пакет, "пакет", обязательные)
    if внешний_пакет["схема"] != ИМЯ_СХЕМЫ:
        raise ОшибкаКонтракта(f"пакет.схема: ожидается {ИМЯ_СХЕМЫ!r}")
    try:
        идентификатор_предложения = uuid.UUID(_непустая_строка(внешний_пакет["идентификатор_предложения"], "идентификатор_предложения"))
    except ValueError as error:
        raise ОшибкаКонтракта(f"идентификатор_предложения: некорректный UUID: {error}") from error
    if str(идентификатор_предложения) != внешний_пакет["идентификатор_предложения"] or ШАБЛОН_ИДЕНТИФИКАТОРА_ПРЕДЛОЖЕНИЯ.fullmatch(внешний_пакет["идентификатор_предложения"]) is None:
        raise ОшибкаКонтракта("идентификатор_предложения: требуется канонический lowercase UUID v4 с RFC-вариантом")

    репозиторий = _закрытый_объект(внешний_пакет["репозиторий"], "репозиторий", {"адрес", "базовый_коммит"})
    адрес = _непустая_строка(репозиторий["адрес"], "репозиторий.адрес")
    разобранный_адрес = urlsplit(адрес)
    if (
        разобранный_адрес.scheme != "https"
        or разобранный_адрес.hostname is None
        or разобранный_адрес.username is not None
        or разобранный_адрес.password is not None
        or разобранный_адрес.query
        or разобранный_адрес.fragment
        or any(символ.isspace() for символ in адрес)
    ):
        raise ОшибкаКонтракта("репозиторий.адрес: требуется публичный HTTPS URL")
    базовый_коммит = _непустая_строка(репозиторий["базовый_коммит"], "репозиторий.базовый_коммит")
    if ШАБЛОН_ПОЛНОГО_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(базовый_коммит) is None:
        raise ОшибкаКонтракта("репозиторий.базовый_коммит: требуется полный 40-символьный OID коммита")

    _непустая_строка(внешний_пакет["утверждение"], "утверждение")
    _список_строк(внешний_пакет["критерии_приёмки"], "критерии_приёмки")
    _список_строк(внешний_пакет["ограничения"], "ограничения")

    сырой_манифест = внешний_пакет["манифест"]
    if not isinstance(сырой_манифест, list) or not сырой_манифест or len(сырой_манифест) > МАКСИМУМ_ЗАПИСЕЙ_МАНИФЕСТА:
        raise ОшибкаКонтракта("манифест: ожидается непустой массив")
    манифест: list[dict[str, str]] = []
    виденные_пути: set[str] = set()
    for индекс, сырая_запись in enumerate(сырой_манифест):
        запись = _закрытый_объект(сырая_запись, f"манифест[{индекс}]", {"путь", "операция"})
        путь = _проверить_путь(запись["путь"])
        операция = запись["операция"]
        if операция not in {"добавить", "изменить", "удалить"}:
            raise ОшибкаКонтракта(f"манифест[{индекс}].операция: недопустимое значение")
        if путь.casefold() in виденные_пути:
            raise ОшибкаКонтракта(f"манифест: повтор или регистронезависимая коллизия пути {путь!r}")
        виденные_пути.add(путь.casefold())
        манифест.append({"путь": путь, "операция": операция})
    if манифест != sorted(манифест, key=lambda элемент: элемент["путь"].encode("utf-8")):
        raise ОшибкаКонтракта("манифест: записи должны быть отсортированы по UTF-8 пути")

    проверки = внешний_пакет["заявленные_проверки"]
    if not isinstance(проверки, list) or not проверки or len(проверки) > МАКСИМУМ_ЭЛЕМЕНТОВ_СПИСКА:
        raise ОшибкаКонтракта("заявленные_проверки: ожидается непустой массив")
    for индекс, сырая_проверка in enumerate(проверки):
        проверка = _закрытый_объект(
            сырая_проверка,
            f"заявленные_проверки[{индекс}]",
            {"название", "статус", "свидетельство", "причина"},
        )
        _непустая_строка(проверка["название"], f"заявленные_проверки[{индекс}].название")
        значение_статуса = проверка["статус"]
        if значение_статуса not in {"пройдена", "неуспешна", "неопределённо", "не_запускалась"}:
            raise ОшибкаКонтракта(f"заявленные_проверки[{индекс}].статус: недопустимое значение")
        свидетельство = проверка["свидетельство"]
        причина = проверка["причина"]
        if свидетельство is not None:
            _непустая_строка(свидетельство, f"заявленные_проверки[{индекс}].свидетельство")
        if причина is not None:
            _непустая_строка(причина, f"заявленные_проверки[{индекс}].причина")
        if значение_статуса in {"пройдена", "неуспешна"} and свидетельство is None:
            raise ОшибкаКонтракта(f"заявленные_проверки[{индекс}]: {значение_статуса} требует свидетельство")
        if значение_статуса in {"неопределённо", "не_запускалась"} and причина is None:
            raise ОшибкаКонтракта(f"заявленные_проверки[{индекс}]: {значение_статуса} требует причину")

    объект_патча = _закрытый_объект(
        внешний_пакет["патч"],
        "патч",
        {"формат", "кодировка", "размер_в_байтах", "хэш_sha256", "данные"},
    )
    if объект_патча["формат"] != "полный-бинарный-патч-git-v1":
        raise ОшибкаКонтракта("патч.формат: требуется полный-бинарный-патч-git-v1")
    if объект_патча["кодировка"] != "base64":
        raise ОшибкаКонтракта("патч.кодировка: требуется base64")
    размер_в_байтах = объект_патча["размер_в_байтах"]
    if not isinstance(размер_в_байтах, int) or isinstance(размер_в_байтах, bool) or not (1 <= размер_в_байтах <= МАКСИМУМ_БАЙТОВ_ПАТЧА):
        raise ОшибкаКонтракта(f"патч.размер_в_байтах: допустим диапазон 1..{МАКСИМУМ_БАЙТОВ_ПАТЧА}")
    хэш_патча = объект_патча["хэш_sha256"]
    if not isinstance(хэш_патча, str) or re.fullmatch(r"[0-9a-f]{64}", хэш_патча) is None:
        raise ОшибкаКонтракта("патч.хэш_sha256: требуется SHA-256 в нижнем регистре")
    данные = объект_патча["данные"]
    if not isinstance(данные, str) or not данные:
        raise ОшибкаКонтракта("патч.данные: ожидается непустая Base64-строка")
    ожидаемые_символы_кодировки = 4 * ((размер_в_байтах + 2) // 3)
    if len(данные) != ожидаемые_символы_кодировки or len(данные) > МАКСИМУМ_СИМВОЛОВ_КОДИРОВКИ:
        raise ОшибкаКонтракта(
            f"патч.данные: длина {len(данные)} не соответствует объявленному размеру {размер_в_байтах}"
        )
    try:
        патч = base64.b64decode(данные, validate=True)
    except (binascii.Error, ValueError) as error:
        raise ОшибкаКонтракта(f"патч.данные: некорректный Base64: {error}") from error
    if len(патч) != размер_в_байтах:
        raise ОшибкаКонтракта(f"патч.размер_в_байтах: объявлено {размер_в_байтах}, получено {len(патч)}")
    фактический_хэш = hashlib.sha256(патч).hexdigest()
    if фактический_хэш != хэш_патча:
        raise ОшибкаКонтракта(f"патч.хэш_sha256: ожидалось {хэш_патча}, получено {фактический_хэш}")
    if b"\x00" in патч:
        raise ОшибкаКонтракта("patch: NUL запрещён; бинарные данные должны находиться в Git binary patch")
    отклонить_известные_секреты(патч, "патч")
    return манифест, патч


def декодировать_базу85_системы_версий(строки: Sequence[str], имя: str) -> bytes:
    результат = bytearray()
    for номер, строка in enumerate(строки):
        if not строка:
            raise ОшибкаКонтракта(f"{имя}: пустая строка внутри Base85-данных")
        первый = строка[0]
        if "A" <= первый <= "Z":
            длина = ord(первый) - ord("A") + 1
        elif "a" <= первый <= "z":
            длина = ord(первый) - ord("a") + 27
        else:
            raise ОшибкаКонтракта(f"{имя}: некорректный префикс длины Base85 в строке {номер}")
        ожидаемая_длина = 1 + 5 * ((длина + 3) // 4)
        if len(строка) != ожидаемая_длина:
            raise ОшибкаКонтракта(
                f"{имя}: длина Base85-строки {номер} равна {len(строка)}, ожидалось {ожидаемая_длина}"
            )
        декодированная_строка = bytearray()
        for начало in range(1, len(строка), 5):
            значение = 0
            for символ in строка[начало : начало + 5]:
                цифра = ЗНАЧЕНИЯ_БАЗЫ85_СИСТЕМЫ_ВЕРСИЙ.get(символ)
                if цифра is None:
                    raise ОшибкаКонтракта(f"{имя}: недопустимый символ Git Base85 {символ!r}")
                значение = значение * 85 + цифра
            if значение > 0xFFFFFFFF:
                raise ОшибкаКонтракта(f"{имя}: переполнение 32-битной группы Git Base85")
            декодированная_строка.extend(значение.to_bytes(4, "big"))
        результат.extend(декодированная_строка[:длина])
    return bytes(результат)


def ограниченно_распаковать_сжатые_данные(
    сжатые_данные: bytes, ожидаемый_размер: int, имя: str
) -> bytes:
    распаковщик = zlib.decompressobj()
    результат = bytearray()
    остаток = сжатые_данные
    try:
        while True:
            оставшийся_предел = ожидаемый_размер + 1 - len(результат)
            if оставшийся_предел <= 0:
                raise ОшибкаКонтракта(f"{имя}: zlib-данные превышают объявленный размер {ожидаемый_размер}")
            порция = распаковщик.decompress(остаток, min(65_536, оставшийся_предел))
            результат.extend(порция)
            if len(результат) > ожидаемый_размер:
                raise ОшибкаКонтракта(f"{имя}: zlib-данные превышают объявленный размер {ожидаемый_размер}")
            остаток = распаковщик.unconsumed_tail
            if распаковщик.eof:
                if остаток or распаковщик.unused_data:
                    raise ОшибкаКонтракта(f"{имя}: лишние данные после zlib-потока")
                break
            if not остаток:
                raise ОшибкаКонтракта(f"{имя}: незавершённый zlib-поток")
    except zlib.error as error:
        raise ОшибкаКонтракта(f"{имя}: некорректный zlib-поток: {error}") from error
    if len(результат) != ожидаемый_размер:
        raise ОшибкаКонтракта(
            f"{имя}: распаковано {len(результат)} байт, объявлено {ожидаемый_размер}"
        )
    return bytes(результат)


def прочитать_размер_дельты(данные: bytes, позиция: int, имя: str) -> tuple[int, int]:
    значение = 0
    сдвиг = 0
    while True:
        if позиция >= len(данные) or сдвиг >= 64:
            raise ОшибкаКонтракта(f"{имя}: повреждённый varint размера delta")
        байт = данные[позиция]
        позиция += 1
        значение |= (байт & 0x7F) << сдвиг
        if not байт & 0x80:
            return значение, позиция
        сдвиг += 7


def проверить_программу_дельты(данные: bytes, имя: str) -> tuple[int, int]:
    размер_источника, позиция = прочитать_размер_дельты(данные, 0, имя)
    размер_результата, позиция = прочитать_размер_дельты(данные, позиция, имя)
    if размер_источника > МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА:
        raise ОшибкаКонтракта(f"{имя}: размер источника delta {размер_источника} превышает лимит")
    if размер_результата > МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА:
        raise ОшибкаКонтракта(f"{имя}: размер результата delta {размер_результата} превышает лимит до применения")
    произведено = 0
    while позиция < len(данные):
        команда = данные[позиция]
        позиция += 1
        if команда & 0x80:
            смещение = 0
            размер_копии = 0
            for маска, сдвиг in ((0x01, 0), (0x02, 8), (0x04, 16), (0x08, 24)):
                if команда & маска:
                    if позиция >= len(данные):
                        raise ОшибкаКонтракта(f"{имя}: усечённое смещение copy-команды delta")
                    смещение |= данные[позиция] << сдвиг
                    позиция += 1
            for маска, сдвиг in ((0x10, 0), (0x20, 8), (0x40, 16)):
                if команда & маска:
                    if позиция >= len(данные):
                        raise ОшибкаКонтракта(f"{имя}: усечённый размер copy-команды delta")
                    размер_копии |= данные[позиция] << сдвиг
                    позиция += 1
            if размер_копии == 0:
                размер_копии = 0x10000
            if смещение + размер_копии > размер_источника:
                raise ОшибкаКонтракта(f"{имя}: copy-команда delta выходит за источник")
            произведено += размер_копии
        else:
            размер_вставки = команда & 0x7F
            if размер_вставки == 0 or позиция + размер_вставки > len(данные):
                raise ОшибкаКонтракта(f"{имя}: повреждённая insert-команда delta")
            позиция += размер_вставки
            произведено += размер_вставки
        if произведено > размер_результата:
            raise ОшибкаКонтракта(f"{имя}: команды delta производят больше объявленного результата")
    if произведено != размер_результата:
        raise ОшибкаКонтракта(
            f"{имя}: команды delta производят {произведено} байт, объявлено {размер_результата}"
        )
    return размер_источника, размер_результата


def разобрать_бинарные_фрагменты(
    раздел: Sequence[str],
    индекс_маркера: int,
    путь: str,
    доступные_байты_распаковки: int,
) -> tuple[БинарныйФрагмент, ...]:
    сырые_фрагменты: list[tuple[str, int, tuple[str, ...]]] = []
    позиция = индекс_маркера + 1
    while позиция < len(раздел):
        while позиция < len(раздел) and раздел[позиция] == "":
            позиция += 1
        if позиция >= len(раздел):
            break
        заголовок = ШАБЛОН_РАЗМЕРА_БИНАРНОГО_ФРАГМЕНТА.fullmatch(раздел[позиция])
        if заголовок is None:
            raise ОшибкаКонтракта(f"patch: бинарный раздел {путь!r} содержит данные вне фрагмента")
        вид = заголовок.group(1)
        объявленный_размер = int(заголовок.group(2))
        if объявленный_размер > МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА:
            raise ОшибкаКонтракта(
                f"patch: бинарный размер для {путь!r} превышает лимит {МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА} байт до применения"
            )
        позиция += 1
        строки_данных: list[str] = []
        while позиция < len(раздел) and раздел[позиция] != "":
            строки_данных.append(раздел[позиция])
            позиция += 1
        if not строки_данных:
            raise ОшибкаКонтракта(f"patch: бинарный фрагмент {путь!r} не содержит Base85-данных")
        сырые_фрагменты.append((вид, объявленный_размер, tuple(строки_данных)))
        if len(сырые_фрагменты) > 2:
            raise ОшибкаКонтракта(
                f"patch: бинарный раздел {путь} должен содержать ровно forward- и reverse-фрагменты"
            )
    if len(сырые_фрагменты) != 2:
        raise ОшибкаКонтракта(
            f"patch: бинарный раздел {путь} должен содержать ровно forward- и reverse-фрагменты"
        )
    объявленная_распаковка = sum(размер for _вид, размер, _строки in сырые_фрагменты)
    if объявленная_распаковка > доступные_байты_распаковки:
        raise ОшибкаКонтракта(
            f"patch: бинарный раздел {путь!r} исчерпывает суммарный лимит распаковки "
            f"{МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА} байт до декодирования"
        )

    фрагменты: list[БинарныйФрагмент] = []
    for вид, объявленный_размер, строки_данных in сырые_фрагменты:
        сжатые_данные = декодировать_базу85_системы_версий(строки_данных, f"patch {путь!r} {вид}")
        распакованные_данные = ограниченно_распаковать_сжатые_данные(
            сжатые_данные, объявленный_размер, f"patch {путь!r} {вид}"
        )
        if вид == "literal":
            отклонить_известные_секреты(распакованные_данные, f"patch {путь!r} literal")
            фрагменты.append(
                БинарныйФрагмент(
                    вид=вид,
                    размер_распакованных_данных=объявленный_размер,
                    размер_источника=None,
                    размер_результата=объявленный_размер,
                )
            )
        else:
            размер_источника, размер_результата = проверить_программу_дельты(
                распакованные_данные, f"patch {путь!r} delta"
            )
            фрагменты.append(
                БинарныйФрагмент(
                    вид=вид,
                    размер_распакованных_данных=объявленный_размер,
                    размер_источника=размер_источника,
                    размер_результата=размер_результата,
                )
            )
    return tuple(фрагменты)


def разобрать_патч(патч: bytes) -> tuple[ЗаписьПатча, ...]:
    try:
        текст = патч.decode("utf-8")
    except UnicodeDecodeError as error:
        raise ОшибкаКонтракта(f"patch: заголовки и Git binary patch должны быть UTF-8: {error}") from error
    if not текст.endswith("\n"):
        raise ОшибкаКонтракта("patch: требуется завершающий LF")
    строки = текст.splitlines()
    начала = [индекс for индекс, строка in enumerate(строки) if строка.startswith("diff --git ")]
    if not начала or начала[0] != 0:
        raise ОшибкаКонтракта("patch: ожидается один или несколько разделов diff --git без префикса")
    записи: list[ЗаписьПатча] = []
    суммарный_размер_распакованных_фрагментов = 0
    суммарные_размеры_результатов = {"forward": 0, "reverse": 0}
    for позиция, начало in enumerate(начала):
        конец = начала[позиция + 1] if позиция + 1 < len(начала) else len(строки)
        раздел = строки[начало:конец]
        заголовок = ШАБЛОН_ЗАГОЛОВКА_РАЗЛИЧИЙ.fullmatch(раздел[0])
        if заголовок is None:
            raise ОшибкаКонтракта(f"patch: неоднозначный или экранированный diff-заголовок {раздел[0]!r}")
        старый_путь, новый_путь = заголовок.groups()
        if старый_путь != новый_путь:
            raise ОшибкаКонтракта("patch: rename/copy не поддерживается версией 1")
        путь = _проверить_путь(старый_путь)
        if any(строка.startswith(("rename ", "copy ", "similarity index ")) for строка in раздел):
            raise ОшибкаКонтракта("patch: rename/copy не поддерживается версией 1")
        операция = "изменить"
        if any(строка.startswith("new file mode ") for строка in раздел):
            операция = "добавить"
        if any(строка.startswith("deleted file mode ") for строка in раздел):
            if операция == "добавить":
                raise ОшибкаКонтракта(f"patch: противоречивые режимы для {путь}")
            операция = "удалить"
        старые_заголовки = [строка for строка in раздел if строка.startswith("--- ")]
        новые_заголовки = [строка for строка in раздел if строка.startswith("+++ ")]
        маркеры_бинарности = [строка for строка in раздел if строка == "GIT binary patch"]
        бинарные_фрагменты: tuple[БинарныйФрагмент, ...] = ()
        if маркеры_бинарности:
            if len(маркеры_бинарности) != 1 or старые_заголовки or новые_заголовки:
                raise ОшибкаКонтракта(f"patch: бинарный раздел {путь} имеет неоднозначные заголовки")
            индекс_маркера = раздел.index("GIT binary patch")
            бинарные_фрагменты = разобрать_бинарные_фрагменты(
                раздел,
                индекс_маркера,
                путь,
                МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА
                - суммарный_размер_распакованных_фрагментов,
            )
            суммарный_размер_распакованных_фрагментов += sum(
                фрагмент.размер_распакованных_данных for фрагмент in бинарные_фрагменты
            )
            if суммарный_размер_распакованных_фрагментов > МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА:
                raise ОшибкаКонтракта(
                    "patch: суммарный распакованный размер binary-fragments "
                    f"{суммарный_размер_распакованных_фрагментов} превышает лимит "
                    f"{МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА} байт до применения"
                )
            for направление, индекс_фрагмента in (("forward", 0), ("reverse", 1)):
                суммарные_размеры_результатов[направление] += бинарные_фрагменты[
                    индекс_фрагмента
                ].размер_результата
                if суммарные_размеры_результатов[направление] > МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА:
                    raise ОшибкаКонтракта(
                        f"patch: сумма результатов {направление}-фрагментов "
                        f"{суммарные_размеры_результатов[направление]} превышает лимит "
                        f"{МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА} байт до применения"
                    )
            if операция == "добавить" and бинарные_фрагменты[1].размер_результата != 0:
                raise ОшибкаКонтракта(f"patch: reverse-фрагмент добавления {путь!r} должен описывать пустой объект")
            if операция == "удалить" and бинарные_фрагменты[0].размер_результата != 0:
                raise ОшибкаКонтракта(f"patch: forward-фрагмент удаления {путь!r} должен описывать пустой объект")
        else:
            if len(старые_заголовки) != 1 or len(новые_заголовки) != 1:
                raise ОшибкаКонтракта(f"patch: для {путь} требуются ровно один --- и один +++ заголовок")
            ожидаемый_старый_заголовок = "--- /dev/null" if операция == "добавить" else f"--- a/{путь}"
            ожидаемый_новый_заголовок = "+++ /dev/null" if операция == "удалить" else f"+++ b/{путь}"
            if старые_заголовки[0] != ожидаемый_старый_заголовок or новые_заголовки[0] != ожидаемый_новый_заголовок:
                raise ОшибкаКонтракта(f"patch: заголовки ---/+++ для {путь} не совпадают с diff --git")
        строки_режима = [
            строка
            for строка in раздел
            if строка.startswith(("new file mode ", "deleted file mode ", "old mode ", "new mode "))
        ]
        for строка_режима in строки_режима:
            режим = строка_режима.rsplit(" ", 1)[-1]
            if режим not in РАЗРЕШЁННЫЕ_РЕЖИМЫ:
                raise ОшибкаКонтракта(f"patch: режим {режим} запрещён; symlink/gitlink и специальные файлы не принимаются")
        строки_индекса = [строка for строка in раздел if строка.startswith("index ")]
        if len(строки_индекса) != 1:
            raise ОшибкаКонтракта(f"patch: для {путь} требуется ровно одна full-index строка")
        совпадение_индекса = ШАБЛОН_ИНДЕКСА_ПАТЧА.fullmatch(строки_индекса[0])
        if совпадение_индекса is None:
            raise ОшибкаКонтракта(f"patch: для {путь} требуется полный 40- или 64-символьный index")
        старый_идентификатор_объекта, новый_идентификатор_объекта, режим_индекса = совпадение_индекса.groups()
        if len(старый_идентификатор_объекта) != len(новый_идентификатор_объекта):
            raise ОшибкаКонтракта(f"patch: длины OID для {путь} не совпадают")
        if режим_индекса is not None and режим_индекса not in РАЗРЕШЁННЫЕ_РЕЖИМЫ:
            raise ОшибкаКонтракта(f"patch: режим {режим_индекса} запрещён")
        if операция == "добавить" and set(старый_идентификатор_объекта) != {"0"}:
            raise ОшибкаКонтракта(f"patch: add для {путь} требует нулевой старый OID")
        if операция == "удалить" and set(новый_идентификатор_объекта) != {"0"}:
            raise ОшибкаКонтракта(f"patch: delete для {путь} требует нулевой новый OID")
        записи.append(
            ЗаписьПатча(
                путь=путь,
                операция=операция,
                старый_идентификатор_объекта=старый_идентификатор_объекта,
                новый_идентификатор_объекта=новый_идентификатор_объекта,
                бинарный=bool(маркеры_бинарности),
                бинарные_фрагменты=бинарные_фрагменты,
            )
        )
    полные_ключи_путей = [нормализованный_ключ_пути(запись.путь) for запись in записи]
    if len(полные_ключи_путей) != len(set(полные_ключи_путей)):
        raise ОшибкаКонтракта("patch: повтор или NFC/casefold-коллизия пути")
    множество_полных_ключей = set(полные_ключи_путей)
    предложенные_префиксы: dict[tuple[str, ...], set[str]] = {}
    for запись in записи:
        части = PurePosixPath(запись.путь).parts
        for длина in range(1, len(части) + 1):
            фактический_префикс = "/".join(части[:длина])
            ключ_префикса = нормализованный_ключ_пути(фактический_префикс)
            предложенные_префиксы.setdefault(ключ_префикса, set()).add(фактический_префикс)
            if длина < len(части) and ключ_префикса in множество_полных_ключей:
                raise ОшибкаКонтракта(
                    f"patch: предложенный путь {запись.путь!r} имеет предложенный файловый предок "
                    f"{фактический_префикс!r}"
                )
    for варианты in предложенные_префиксы.values():
        if len(варианты) > 1:
            raise ОшибкаКонтракта(
                f"patch: NFC/casefold-коллизия предложенных префиксов {sorted(варианты)!r}"
            )
    return tuple(записи)


def разделы_патча(патч: bytes) -> tuple[bytes, ...]:
    строки = патч.splitlines(keepends=True)
    начала = [индекс for индекс, строка in enumerate(строки) if строка.startswith(b"diff --git ")]
    return tuple(
        b"".join(строки[начало : начала[позиция + 1] if позиция + 1 < len(начала) else len(строки)])
        for позиция, начало in enumerate(начала)
    )


def _система_версий(корень_проверяемого_репозитория: Path, *аргументы_команды: str, входные_байты: bytes | None = None) -> bytes:
    try:
        результат = subprocess.run(
            ["git", "--literal-pathspecs", *аргументы_команды],
            cwd=корень_проверяемого_репозитория,
            env=чистая_среда_системы_версий(),
            input=входные_байты,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
            timeout=ТАЙМ_АУТ_СИСТЕМЫ_ВЕРСИЙ_В_СЕКУНДАХ,
        )
    except subprocess.TimeoutExpired as error:
        raise ОшибкаКонтракта(f"git {' '.join(аргументы_команды)}: превышен тайм-аут {ТАЙМ_АУТ_СИСТЕМЫ_ВЕРСИЙ_В_СЕКУНДАХ} с") from error
    if результат.returncode != 0:
        подробность = результат.stderr.decode("utf-8", "replace").strip() or результат.stdout.decode("utf-8", "replace").strip()
        raise ОшибкаКонтракта(f"git {' '.join(аргументы_команды)}: {подробность or 'команда завершилась неуспешно'}")
    return результат.stdout


def нормализовать_адрес_репозитория(адрес: str) -> str:
    разобранный = urlsplit(адрес.strip())
    путь = разобранный.path.rstrip("/")
    if путь.endswith(".git"):
        путь = путь[:-4]
    return urlunsplit((разобранный.scheme.lower(), разобранный.netloc.lower(), путь, "", ""))


def проверить_репозиторий(корень_проверяемого_репозитория: Path, внешний_пакет: dict[str, Any], патч: bytes, записи: Iterable[ЗаписьПатча]) -> None:
    корень = корень_проверяемого_репозитория.resolve(strict=True)
    верхний_корень = Path(_система_версий(корень, "rev-parse", "--show-toplevel").decode().strip()).resolve(strict=True)
    if верхний_корень != корень:
        raise ОшибкаКонтракта(f"корень-репозитория: ожидается корень checkout {верхний_корень}, получено {корень}")
    каталог_системы_версий = Path(_система_версий(корень, "rev-parse", "--absolute-git-dir").decode().strip()).resolve(strict=True)
    if not (корень / ".git").is_dir() or каталог_системы_версий != (корень / ".git").resolve(strict=True):
        raise ОшибкаКонтракта("корень-репозитория: требуется первичный checkout, linked worktree запрещён")
    символическая_ссылка = _система_версий(корень, "symbolic-ref", "HEAD").decode().strip()
    if символическая_ссылка != "refs/heads/master":
        raise ОшибкаКонтракта(f"HEAD: ожидается refs/heads/master, получено {символическая_ссылка}")
    вершина = _система_версий(корень, "rev-parse", "HEAD^{commit}").decode().strip()
    базовый_коммит = внешний_пакет["репозиторий"]["базовый_коммит"]
    if вершина != базовый_коммит:
        raise ОшибкаКонтракта(f"репозиторий.базовый_коммит: пакет закреплён на {базовый_коммит}, текущий HEAD {вершина}")
    опубликованная_вершина = _система_версий(корень, "rev-parse", "refs/remotes/origin/master^{commit}").decode().strip()
    if опубликованная_вершина != базовый_коммит:
        raise ОшибкаКонтракта(
            f"репозиторий.базовый_коммит: локальный origin/master {опубликованная_вершина} не совпадает с базой {базовый_коммит}"
        )
    удалённый_адрес = _система_версий(корень, "remote", "get-url", "origin").decode().strip()
    ожидаемый_удалённый_адрес = внешний_пакет["репозиторий"]["адрес"]
    if нормализовать_адрес_репозитория(удалённый_адрес) != нормализовать_адрес_репозитория(ожидаемый_удалённый_адрес):
        raise ОшибкаКонтракта(f"репозиторий.адрес: пакет указывает {ожидаемый_удалённый_адрес}, origin указывает {удалённый_адрес}")

    список_записей = tuple(записи)
    try:
        сырое_базовое_дерево = _система_версий(корень, "ls-tree", "-r", "-z", "--full-tree", базовый_коммит)
        базовое_дерево: dict[str, tuple[str, str]] = {}
        ссылки_системы_версий: set[str] = set()
        for сырая_запись in сырое_базовое_дерево.split(b"\0"):
            if not сырая_запись:
                continue
            метаданные, сырой_путь = сырая_запись.split(b"\t", 1)
            режим, тип_объекта, идентификатор_объекта = метаданные.decode("ascii").split()
            путь_дерева = сырой_путь.decode("utf-8")
            базовое_дерево[путь_дерева] = (режим, идентификатор_объекта)
            if режим == "160000" and тип_объекта == "commit":
                ссылки_системы_версий.add(путь_дерева)
    except (UnicodeDecodeError, ValueError) as error:
        raise ОшибкаКонтракта(f"базовое дерево Git: некорректная запись: {error}") from error

    префиксы_базового_дерева: dict[tuple[str, ...], set[str]] = {}
    for путь_дерева in базовое_дерево:
        части_дерева = PurePosixPath(путь_дерева).parts
        for длина in range(1, len(части_дерева) + 1):
            фактический_префикс = "/".join(части_дерева[:длина])
            ключ_префикса = нормализованный_ключ_пути(фактический_префикс)
            префиксы_базового_дерева.setdefault(ключ_префикса, set()).add(фактический_префикс)

    for запись in список_записей:
        части = PurePosixPath(запись.путь).parts
        for длина in range(1, len(части) + 1):
            фактический_префикс = "/".join(части[:длина])
            ключ_префикса = нормализованный_ключ_пути(фактический_префикс)
            базовые_варианты = префиксы_базового_дерева.get(ключ_префикса, set())
            if базовые_варианты and (len(базовые_варианты) != 1 or фактический_префикс not in базовые_варианты):
                raise ОшибкаКонтракта(
                    f"path {запись.путь!r}: casefold/NFC-коллизия с базовым путём {sorted(базовые_варианты)!r}"
                )
            if длина < len(части) and фактический_префикс in базовое_дерево:
                raise ОшибкаКонтракта(f"path {запись.путь!r}: предок {фактический_префикс!r} является файлом базы")
        if запись.операция == "добавить" and нормализованный_ключ_пути(запись.путь) in префиксы_базового_дерева:
            raise ОшибкаКонтракта(f"path {запись.путь!r}: добавление конфликтует с файлом или каталогом базы")

        кандидат = корень
        for часть in PurePosixPath(запись.путь).parts:
            кандидат = кандидат / часть
            try:
                режим = кандидат.lstat().st_mode
            except FileNotFoundError:
                break
            if stat.S_ISLNK(режим):
                raise ОшибкаКонтракта(f"path {запись.путь!r}: компонент {кандидат.relative_to(корень)} является symlink")
        for длина in range(1, len(части) + 1):
            префикс = "/".join(части[:длина])
            if префикс in ссылки_системы_версий:
                raise ОшибкаКонтракта(f"path {запись.путь!r}: предок {префикс!r} является gitlink")

        if запись.операция != "добавить":
            базовая_запись = базовое_дерево.get(запись.путь)
            if базовая_запись is None or базовая_запись[0] not in РАЗРЕШЁННЫЕ_РЕЖИМЫ:
                raise ОшибкаКонтракта(f"path {запись.путь!r}: базовый режим не является обычным файлом")
            базовый_идентификатор_объекта = базовая_запись[1]
            if базовый_идентификатор_объекта != запись.старый_идентификатор_объекта:
                raise ОшибкаКонтракта(
                    f"patch full-index: для {запись.путь!r} старый OID {запись.старый_идентификатор_объекта} "
                    f"не совпадает с blob базы {базовый_идентификатор_объекта}"
                )
        elif запись.путь in базовое_дерево:
            raise ОшибкаКонтракта(f"patch: add для {запись.путь!r} перекрывает существующий путь базы")

    старые_идентификаторы = tuple(
        dict.fromkeys(
            запись.старый_идентификатор_объекта
            for запись in список_записей
            if запись.операция != "добавить"
        )
    )
    размеры_базовых_объектов: dict[str, int] = {}
    if старые_идентификаторы:
        вход_проверки_базы = "".join(f"{идентификатор}\n" for идентификатор in старые_идентификаторы).encode("ascii")
        выход_проверки_базы = _система_версий(корень, "cat-file", "--batch-check", входные_байты=вход_проверки_базы)
        строки_проверки_базы = выход_проверки_базы.decode("ascii").splitlines()
        if len(строки_проверки_базы) != len(старые_идентификаторы):
            raise ОшибкаКонтракта("базовое дерево Git: неполный batch-check объектов")
        for ожидаемый_идентификатор, строка in zip(старые_идентификаторы, строки_проверки_базы, strict=True):
            try:
                фактический_идентификатор, тип_объекта, текст_размера = строка.split()
                размер_объекта = int(текст_размера)
            except ValueError as error:
                raise ОшибкаКонтракта(f"базовое дерево Git: некорректный batch-check: {строка!r}") from error
            if фактический_идентификатор != ожидаемый_идентификатор or тип_объекта != "blob":
                raise ОшибкаКонтракта(f"базовое дерево Git: ожидался blob {ожидаемый_идентификатор}, получено {строка}")
            if размер_объекта > МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА:
                raise ОшибкаКонтракта(
                    f"базовый blob {ожидаемый_идентификатор}: {размер_объекта} байт превышают лимит "
                    f"{МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА} до применения"
                )
            размеры_базовых_объектов[ожидаемый_идентификатор] = размер_объекта

    for запись in список_записей:
        if not запись.бинарный:
            continue
        прямой_фрагмент, обратный_фрагмент = запись.бинарные_фрагменты
        размер_старого_объекта = (
            0
            if запись.операция == "добавить"
            else размеры_базовых_объектов[запись.старый_идентификатор_объекта]
        )
        if (
            прямой_фрагмент.вид == "delta"
            and прямой_фрагмент.размер_источника != размер_старого_объекта
        ):
            raise ОшибкаКонтракта(
                f"patch: forward delta для {запись.путь!r} объявляет источник "
                f"{прямой_фрагмент.размер_источника}, ожидалось {размер_старого_объекта}"
            )
        if обратный_фрагмент.размер_результата != размер_старого_объекта:
            raise ОшибкаКонтракта(
                f"patch: reverse-фрагмент для {запись.путь!r} объявляет результат "
                f"{обратный_фрагмент.размер_результата}, ожидалось {размер_старого_объекта}"
            )
        if (
            обратный_фрагмент.вид == "delta"
            and обратный_фрагмент.размер_источника != прямой_фрагмент.размер_результата
        ):
            raise ОшибкаКонтракта(
                f"patch: reverse delta для {запись.путь!r} объявляет источник "
                f"{обратный_фрагмент.размер_источника}, ожидалось {прямой_фрагмент.размер_результата}"
            )

    суммарный_размер_базовых_объектов = sum(
        размеры_базовых_объектов[запись.старый_идентификатор_объекта]
        for запись in список_записей
        if запись.операция != "добавить"
    )
    if суммарный_размер_базовых_объектов > МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА:
        raise ОшибкаКонтракта(
            f"базовые blobs: сумма по путям {суммарный_размер_базовых_объектов} байт превышает лимит "
            f"{МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА} до применения"
        )

    заявленные_размеры_бинарных_результатов: dict[str, int] = {}
    for запись in список_записей:
        if not запись.бинарный or запись.операция == "удалить":
            continue
        заявленный_размер = запись.бинарные_фрагменты[0].размер_результата
        прежний_размер = заявленные_размеры_бинарных_результатов.setdefault(
            запись.новый_идентификатор_объекта, заявленный_размер
        )
        if прежний_размер != заявленный_размер:
            raise ОшибкаКонтракта(
                f"patch: одинаковый новый OID {запись.новый_идентификатор_объекта} имеет разные "
                f"объявленные размеры {прежний_размер} и {заявленный_размер}"
            )

    новые_идентификаторы = tuple(
        dict.fromkeys(
            запись.новый_идентификатор_объекта
            for запись in список_записей
            if запись.операция != "удалить"
        )
    )
    существующие_размеры_новых_объектов: dict[str, int] = {}
    if новые_идентификаторы:
        вход_проверки_новых = "".join(f"{идентификатор}\n" for идентификатор in новые_идентификаторы).encode(
            "ascii"
        )
        выход_проверки_новых = _система_версий(
            корень, "cat-file", "--batch-check", входные_байты=вход_проверки_новых
        )
        строки_проверки_новых = выход_проверки_новых.decode("ascii").splitlines()
        if len(строки_проверки_новых) != len(новые_идентификаторы):
            raise ОшибкаКонтракта("Git object store: неполный batch-check заявленных новых объектов")
        for ожидаемый_идентификатор, строка in zip(
            новые_идентификаторы, строки_проверки_новых, strict=True
        ):
            части_строки = строка.split()
            if части_строки == [ожидаемый_идентификатор, "missing"]:
                continue
            try:
                фактический_идентификатор, тип_объекта, текст_размера = части_строки
                размер_объекта = int(текст_размера)
            except ValueError as error:
                raise ОшибкаКонтракта(
                    f"Git object store: некорректный batch-check нового OID: {строка!r}"
                ) from error
            if фактический_идентификатор != ожидаемый_идентификатор or тип_объекта != "blob":
                raise ОшибкаКонтракта(
                    f"Git object store: заявленный новый OID должен быть blob или отсутствовать: {строка}"
                )
            if размер_объекта > МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА:
                raise ОшибкаКонтракта(
                    f"существующий новый blob {ожидаемый_идентификатор}: {размер_объекта} байт превышают "
                    f"лимит {МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА} до применения"
                )
            существующие_размеры_новых_объектов[ожидаемый_идентификатор] = размер_объекта

    for идентификатор, заявленный_размер in заявленные_размеры_бинарных_результатов.items():
        существующий_размер = существующие_размеры_новых_объектов.get(идентификатор)
        if существующий_размер is not None and существующий_размер != заявленный_размер:
            raise ОшибкаКонтракта(
                f"patch: существующий новый blob {идентификатор} имеет размер {существующий_размер}, "
                f"forward-фрагмент объявляет {заявленный_размер}"
            )

    текстовые_результаты = [
        запись for запись in список_записей if not запись.бинарный and запись.операция != "удалить"
    ]
    for запись in текстовые_результаты:
        размер_старого_объекта = (
            0
            if запись.операция == "добавить"
            else размеры_базовых_объектов[запись.старый_идентификатор_объекта]
        )
        верхняя_граница = размер_старого_объекта + len(патч)
        if верхняя_граница > МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА:
            raise ОшибкаКонтракта(
                f"текстовый результат {запись.путь!r}: безопасная верхняя граница {верхняя_граница} байт "
                f"превышает лимит {МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА} до применения"
            )
    верхняя_граница_результатов = sum(
        размеры_базовых_объектов[запись.старый_идентификатор_объекта]
        for запись in текстовые_результаты
        if запись.операция != "добавить"
    )
    if текстовые_результаты:
        верхняя_граница_результатов += len(патч)
    верхняя_граница_результатов += sum(
        запись.бинарные_фрагменты[0].размер_результата
        for запись in список_записей
        if запись.бинарный and запись.операция != "удалить"
    )
    if верхняя_граница_результатов > МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА:
        raise ОшибкаКонтракта(
            f"результирующие blobs: безопасная верхняя граница {верхняя_граница_результатов} байт "
            f"превышает лимит {МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА} до применения"
        )

    путь_реальных_объектов = Path(_система_версий(корень, "rev-parse", "--git-path", "objects").decode().strip())
    if not путь_реальных_объектов.is_absolute():
        путь_реальных_объектов = корень / путь_реальных_объектов
    реальные_объекты = путь_реальных_объектов.resolve(strict=True)

    with tempfile.TemporaryDirectory(prefix="fum-external-contribution-git-") as временный_каталог:
        временный_корень = Path(временный_каталог)
        путь_индекса = временный_корень / "index"
        каталог_объектов = временный_корень / "objects"
        каталог_объектов.mkdir()
        среда = чистая_среда_системы_версий()
        среда["GIT_INDEX_FILE"] = str(путь_индекса)
        среда["GIT_OBJECT_DIRECTORY"] = str(каталог_объектов)
        среда["GIT_ALTERNATE_OBJECT_DIRECTORIES"] = str(реальные_объекты)
        среда["GIT_OPTIONAL_LOCKS"] = "0"

        def запустить_с_временным_индексом(*аргументы: str, входные_байты: bytes | None = None) -> bytes:
            try:
                результат = subprocess.run(
                    ["git", "--literal-pathspecs", *аргументы],
                    cwd=корень,
                    env=среда,
                    input=входные_байты,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    check=False,
                    timeout=ТАЙМ_АУТ_СИСТЕМЫ_ВЕРСИЙ_В_СЕКУНДАХ,
                    preexec_fn=ограничить_ресурсы_системы_версий,
                )
            except subprocess.TimeoutExpired as error:
                raise ОшибкаКонтракта(
                    f"временный Git, {' '.join(аргументы)}: превышен тайм-аут {ТАЙМ_АУТ_СИСТЕМЫ_ВЕРСИЙ_В_СЕКУНДАХ} с"
                ) from error
            except subprocess.SubprocessError as error:
                raise ОшибкаКонтракта(f"временный Git, {' '.join(аргументы)}: не удалось установить ресурсную границу") from error
            if результат.returncode != 0:
                подробность = результат.stderr.decode("utf-8", "replace").strip() or "без диагностики"
                raise ОшибкаКонтракта(f"временный Git index, {' '.join(аргументы)}: {подробность}")
            return результат.stdout

        запустить_с_временным_индексом("read-tree", базовый_коммит)
        запустить_с_временным_индексом("apply", "--cached", "--binary", "--whitespace=error-all", "-", входные_байты=патч)
        сырые_индексированные_записи = запустить_с_временным_индексом("ls-files", "-s", "-z", "--", *(запись.путь for запись in список_записей))
        индексированные_по_путям: dict[str, tuple[str, str]] = {}
        try:
            for сырая_запись in сырые_индексированные_записи.split(b"\0"):
                if not сырая_запись:
                    continue
                метаданные, сырой_путь = сырая_запись.split(b"\t", 1)
                режим, индексированный_идентификатор_объекта, номер_стадии = метаданные.decode("ascii").split()
                if номер_стадии != "0":
                    raise ОшибкаКонтракта("временный Git index: неожиданная конфликтная стадия")
                индексированные_по_путям[сырой_путь.decode("utf-8")] = (режим, индексированный_идентификатор_объекта)
        except (UnicodeDecodeError, ValueError) as error:
            raise ОшибкаКонтракта(f"временный Git index: некорректная запись: {error}") from error

        пути_объектов_по_идентификаторам: dict[str, list[str]] = {}
        for запись in список_записей:
            индексированная_запись = индексированные_по_путям.get(запись.путь)
            if запись.операция == "удалить":
                if индексированная_запись is not None:
                    raise ОшибкаКонтракта(f"patch full-index: удалённый путь {запись.путь!r} остался во временном index")
                continue
            if индексированная_запись is None:
                raise ОшибкаКонтракта(f"patch full-index: путь {запись.путь!r} отсутствует во временном index")
            индексированный_режим, индексированный_идентификатор_объекта = индексированная_запись
            if индексированный_режим not in РАЗРЕШЁННЫЕ_РЕЖИМЫ:
                raise ОшибкаКонтракта(f"patch full-index: режим {индексированный_режим} для {запись.путь!r} запрещён")
            if индексированный_идентификатор_объекта != запись.новый_идентификатор_объекта:
                raise ОшибкаКонтракта(
                    f"patch full-index: для {запись.путь!r} новый OID {запись.новый_идентификатор_объекта} "
                    f"не совпадает с вычисленным blob {индексированный_идентификатор_объекта}"
                )
            пути_объектов_по_идентификаторам.setdefault(индексированный_идентификатор_объекта, []).append(запись.путь)

        идентификаторы_результата = tuple(пути_объектов_по_идентификаторам)
        пакетный_вход = "".join(f"{идентификатор}\n" for идентификатор in идентификаторы_результата).encode("ascii")
        метаданные_результата: list[tuple[str, int]] = []
        размеры_результатов_по_идентификаторам: dict[str, int] = {}
        if идентификаторы_результата:
            сырая_проверка_результатов = запустить_с_временным_индексом(
                "cat-file", "--batch-check", входные_байты=пакетный_вход
            )
            строки_проверки_результатов = сырая_проверка_результатов.decode("ascii").splitlines()
            if len(строки_проверки_результатов) != len(идентификаторы_результата):
                raise ОшибкаКонтракта("временный Git object store: неполный batch-check результатов")
            for ожидаемый_идентификатор, строка in zip(
                идентификаторы_результата, строки_проверки_результатов, strict=True
            ):
                try:
                    фактический_идентификатор, тип_объекта, текст_размера = строка.split()
                    размер_объекта = int(текст_размера)
                except ValueError as error:
                    raise ОшибкаКонтракта(
                        f"временный Git object store: некорректный batch-check: {строка!r}"
                    ) from error
                if фактический_идентификатор != ожидаемый_идентификатор or тип_объекта != "blob":
                    raise ОшибкаКонтракта(
                        f"временный Git object store: ожидался blob {ожидаемый_идентификатор}, получено {строка}"
                    )
                пути = пути_объектов_по_идентификаторам[ожидаемый_идентификатор]
                объединённые_пути = ", ".join(repr(путь) for путь in пути)
                if размер_объекта > МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА:
                    raise ОшибкаКонтракта(
                        f"результирующий blob {объединённые_пути}: {размер_объекта} байт превышают лимит "
                        f"{МАКСИМУМ_БАЙТОВ_ОБЪЕКТА_РЕЗУЛЬТАТА}"
                    )
                метаданные_результата.append((ожидаемый_идентификатор, размер_объекта))
                размеры_результатов_по_идентификаторам[ожидаемый_идентификатор] = размер_объекта

        суммарные_байты_результата = sum(
            размеры_результатов_по_идентификаторам[запись.новый_идентификатор_объекта]
            for запись in список_записей
            if запись.операция != "удалить"
        )
        if суммарные_байты_результата > МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА:
            raise ОшибкаКонтракта(
                f"результирующие blobs: сумма по путям {суммарные_байты_результата} байт превышает лимит "
                f"{МАКСИМУМ_СУММАРНЫХ_БАЙТОВ_РЕЗУЛЬТАТА}"
            )
        for запись in список_записей:
            if not запись.бинарный or запись.операция == "удалить":
                continue
            фактический_размер = размеры_результатов_по_идентификаторам[
                запись.новый_идентификатор_объекта
            ]
            объявленный_размер = запись.бинарные_фрагменты[0].размер_результата
            if фактический_размер != объявленный_размер:
                raise ОшибкаКонтракта(
                    f"patch: forward-фрагмент для {запись.путь!r} объявляет результат "
                    f"{объявленный_размер}, Git вычислил {фактический_размер}"
                )

        пакетный_выход = io.BytesIO(
            запустить_с_временным_индексом("cat-file", "--batch", входные_байты=пакетный_вход)
            if идентификаторы_результата
            else b""
        )
        for ожидаемый_идентификатор, ожидаемый_размер in метаданные_результата:
            try:
                заголовок = пакетный_выход.readline().decode("ascii").rstrip("\n")
                фактический_идентификатор, тип_объекта, текст_размера = заголовок.split()
                размер_объекта = int(текст_размера)
            except (UnicodeDecodeError, ValueError) as error:
                raise ОшибкаКонтракта(f"временный Git object store: некорректный batch-ответ: {error}") from error
            if фактический_идентификатор != ожидаемый_идентификатор or тип_объекта != "blob":
                raise ОшибкаКонтракта(f"временный Git object store: ожидался blob {ожидаемый_идентификатор}, получено {заголовок}")
            if размер_объекта != ожидаемый_размер:
                raise ОшибкаКонтракта(
                    f"временный Git object store: размер blob {ожидаемый_идентификатор} изменился между batch-check и чтением"
                )
            пути = пути_объектов_по_идентификаторам[ожидаемый_идентификатор]
            объединённые_пути = ", ".join(repr(путь) for путь in пути)
            содержимое_объекта = пакетный_выход.read(размер_объекта)
            разделитель = пакетный_выход.read(1)
            if len(содержимое_объекта) != размер_объекта:
                raise ОшибкаКонтракта(f"результирующий blob {объединённые_пути}: размер изменился при чтении")
            if разделитель != b"\n":
                raise ОшибкаКонтракта(f"результирующий blob {объединённые_пути}: некорректный batch-разделитель")
            отклонить_известные_секреты(содержимое_объекта, f"результирующий blob {объединённые_пути}")
        if пакетный_выход.read(1):
            raise ОшибкаКонтракта("временный Git object store: лишние байты в batch-ответе")

        канонический_патч = запустить_с_временным_индексом(
            "-c",
            "core.quotePath=false",
            "diff",
            "--cached",
            "--binary",
            "--full-index",
            "--no-renames",
            "--no-color",
            "--src-prefix=a/",
            "--dst-prefix=b/",
            "--no-ext-diff",
            "--no-textconv",
            базовый_коммит,
            "--",
            *(запись.путь for запись in список_записей),
        )
        канонические_записи = разобрать_патч(канонический_патч)
        исходные_разделы = разделы_патча(патч)
        канонические_разделы = разделы_патча(канонический_патч)
        if len(канонические_записи) != len(список_записей) or len(канонические_разделы) != len(исходные_разделы):
            raise ОшибкаКонтракта("patch: локальная каноническая регенерация дала иной набор разделов")
        for исходная_запись, каноническая_запись, исходный_раздел, канонический_раздел in zip(
            список_записей,
            канонические_записи,
            исходные_разделы,
            канонические_разделы,
            strict=True,
        ):
            if (
                исходная_запись.путь != каноническая_запись.путь
                or исходная_запись.операция != каноническая_запись.операция
            ):
                raise ОшибкаКонтракта("patch: локальная каноническая регенерация изменила путь или операцию")
            if исходная_запись.бинарный and (
                not каноническая_запись.бинарный or исходный_раздел != канонический_раздел
            ):
                raise ОшибкаКонтракта(
                    f"patch: бинарный раздел {исходная_запись.путь!r} не совпадает с локальной канонической регенерацией"
                )

        запустить_с_временным_индексом(
            "apply", "--cached", "--reverse", "--binary", "--whitespace=error-all", "-", входные_байты=патч
        )
        восстановленное_дерево = запустить_с_временным_индексом("write-tree").decode("ascii").strip()
        базовое_дерево_идентификатор = _система_версий(корень, "rev-parse", f"{базовый_коммит}^{{tree}}").decode("ascii").strip()
        if восстановленное_дерево != базовое_дерево_идентификатор:
            raise ОшибкаКонтракта(
                f"patch: обратное применение восстановило дерево {восстановленное_дерево}, ожидалось {базовое_дерево_идентификатор}"
            )


def проверить_пакет(корень_проверяемого_репозитория: Path, байты_пакета: bytes) -> ПроверенныйПакет:
    внешний_пакет = загрузить_байты_джейсон(байты_пакета, "пакет")
    манифест, патч = проверить_форму_пакета(внешний_пакет)
    канонические_байты = (json.dumps(внешний_пакет, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode(
        "utf-8"
    )
    отклонить_известные_секреты(канонические_байты, "пакет")
    записи = разобрать_патч(патч)
    фактический_манифест = [{"путь": запись.путь, "операция": запись.операция} for запись in записи]
    if фактический_манифест != манифест:
        raise ОшибкаКонтракта(f"манифест: объявлено {манифест!r}, patch содержит {фактический_манифест!r}")
    проверить_репозиторий(корень_проверяемого_репозитория, внешний_пакет, патч, записи)
    return ПроверенныйПакет(
        внешний_пакет=внешний_пакет,
        канонический_пакет=канонические_байты,
        патч=патч,
        записи=записи,
        хэш_канонического_пакета=hashlib.sha256(канонические_байты).hexdigest(),
    )


def проверить_путь_запроса(корень_проверяемого_репозитория: Path, путь_запроса: Path) -> str:
    корень = корень_проверяемого_репозитория.resolve(strict=True)
    кандидат = путь_запроса if путь_запроса.is_absolute() else корень / путь_запроса
    разрешённый_путь = кандидат.expanduser().resolve(strict=True)
    try:
        относительный_путь = разрешённый_путь.relative_to(корень)
    except ValueError as error:
        raise ОшибкаКонтракта(f"запрос {путь_запроса}: путь выходит за корень repo") from error
    части = относительный_путь.parts
    if (
        len(части) != 3
        or части[0] != "Журнал"
        or ШАБЛОН_КАТАЛОГА_СЕССИИ.fullmatch(части[1]) is None
        or части[2] != "запрос.md"
        or not разрешённый_путь.is_file()
        or разрешённый_путь.is_symlink()
    ):
        raise ОшибкаКонтракта(f"запрос {путь_запроса}: ожидается обычный Журнал/<сессия>/запрос.md")
    return части[1]


def проверить_путь_архива_сообщений(корень_проверяемого_репозитория: Path, путь_сообщений: Path) -> str:
    сырой_корень = Path(os.path.abspath(корень_проверяемого_репозитория.expanduser()))
    корень = сырой_корень.resolve(strict=True)
    кандидат = путь_сообщений.expanduser() if путь_сообщений.is_absolute() else сырой_корень / путь_сообщений
    абсолютный_кандидат = Path(os.path.abspath(кандидат))
    try:
        относительный_путь = абсолютный_кандидат.relative_to(сырой_корень)
    except ValueError as error:
        raise ОшибкаКонтракта("messages: разрешён только канонический архив внутри текущего repo") from error
    части = относительный_путь.parts
    if (
        len(части) != 7
        or части[:5] != ("Источники", "URL", "https", "chatgpt.com", "share")
        or re.fullmatch(r"[A-Za-z0-9-]+", части[5]) is None
        or части[6] != "chatgpt-share.messages.json"
    ):
        raise ОшибкаКонтракта(
            "messages: ожидается Источники/URL/https/chatgpt.com/share/<id>/chatgpt-share.messages.json"
        )
    текущий = сырой_корень
    for часть in части:
        текущий = текущий / часть
        try:
            режим = текущий.lstat().st_mode
        except FileNotFoundError as error:
            raise ОшибкаКонтракта(f"messages: отсутствует канонический архивный путь {текущий}") from error
        if stat.S_ISLNK(режим):
            raise ОшибкаКонтракта(f"messages: символическая ссылка в архивном пути запрещена: {текущий}")
    if not stat.S_ISREG(абсолютный_кандидат.lstat().st_mode):
        raise ОшибкаКонтракта("messages: архив сообщений должен быть обычным файлом")
    разрешённый_путь = абсолютный_кандидат.resolve(strict=True)
    try:
        разрешённый_относительный_путь = разрешённый_путь.relative_to(корень)
    except ValueError as error:
        raise ОшибкаКонтракта("messages: архив после разрешения выходит за корень repo") from error
    if разрешённый_относительный_путь != относительный_путь:
        raise ОшибкаКонтракта("messages: архивный путь после разрешения символических ссылок изменился")
    return f"https://chatgpt.com/share/{части[5]}"


def проверить_выходной_путь(корень_проверяемого_репозитория: Path, путь: Path, ожидаемое_имя: str, имя_сессии: str) -> Path:
    корень = корень_проверяемого_репозитория.resolve(strict=True)
    кандидат = путь if путь.is_absolute() else корень / путь
    разрешённый_путь = кандидат.expanduser().resolve(strict=False)
    try:
        относительный_путь = разрешённый_путь.relative_to(корень)
    except ValueError as error:
        raise ОшибкаКонтракта(f"output {путь}: разрешены только материалы текущей сессии внутри repo") from error
    части = относительный_путь.parts
    if (
        len(части) != 5
        or части[0] != "Журнал"
        or части[1] != имя_сессии
        or части[2] != "материалы"
        or части[3] != "внешний-вклад"
        or части[4] != ожидаемое_имя
    ):
        raise ОшибкаКонтракта(
            f"output {путь}: ожидается Журнал/<сессия>/материалы/внешний-вклад/{ожидаемое_имя}"
        )
    каталог_сессии = корень / части[0] / части[1]
    каталог_материалов = каталог_сессии / части[2]
    if not каталог_сессии.is_dir() or каталог_сессии.is_symlink():
        raise ОшибкаКонтракта(f"output {путь}: каталог сессии должен уже существовать и не быть symlink")
    if not каталог_материалов.is_dir() or каталог_материалов.is_symlink():
        raise ОшибкаКонтракта(f"output {путь}: каталог материалов должен уже существовать и не быть symlink")
    return разрешённый_путь


def предварительно_проверить_выход(цель: Path, данные: bytes) -> bool:
    try:
        существующий_режим = цель.lstat().st_mode
    except FileNotFoundError:
        return False
    if not stat.S_ISREG(существующий_режим) or stat.S_ISLNK(существующий_режим):
        raise ОшибкаКонтракта(f"output {цель}: ожидается обычный файл")
    if цель.read_bytes() != данные:
        raise ОшибкаКонтракта(f"output {цель}: существующий файл имеет другие байты")
    return True


def атомарно_записать_новый(путь: Path, данные: bytes) -> None:
    путь.parent.mkdir(exist_ok=True)
    родитель = путь.parent.resolve(strict=True)
    цель = родитель / путь.name
    дескриптор, временное_имя = tempfile.mkstemp(prefix=f".{цель.name}.tmp-", dir=родитель)
    временный_файл = Path(временное_имя)
    try:
        with os.fdopen(дескриптор, "wb") as поток:
            поток.write(данные)
            поток.flush()
            os.fsync(поток.fileno())
        os.chmod(временный_файл, 0o644)
        try:
            os.link(временный_файл, цель)
        except FileExistsError as error:
            raise ОшибкаКонтракта(f"output {цель}: файл конкурентно появился; перезапись запрещена") from error
    finally:
        временный_файл.unlink(missing_ok=True)


def извлечь_пакет_из_сообщений(байты_сообщений: bytes) -> tuple[bytes, str, int]:
    отклонить_известные_секреты(байты_сообщений, "messages")
    документ = загрузить_байты_джейсон(байты_сообщений, "messages")
    канонические_байты_сообщений = json.dumps(
        документ, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    отклонить_известные_секреты(канонические_байты_сообщений, "декодированный messages")
    список_сообщений = документ.get("messages")
    if not isinstance(список_сообщений, list):
        raise ОшибкаКонтракта("messages.messages: ожидается массив")
    совпадения: list[tuple[int, str]] = []
    индекс_последнего_хода: int | None = None
    for индекс, сообщение in enumerate(список_сообщений):
        if not isinstance(сообщение, dict):
            raise ОшибкаКонтракта(f"messages.messages[{индекс}]: ожидается объект")
        роль = сообщение.get("role")
        if роль in {"user", "assistant"}:
            индекс_последнего_хода = индекс
        if роль != "assistant" or сообщение.get("content_type") != "text":
            continue
        текст = сообщение.get("text")
        if not isinstance(текст, str):
            raise ОшибкаКонтракта(f"messages.messages[{индекс}].text: ожидается строка")
        открытия = len(re.findall(rf"^```{re.escape(ИМЯ_ОГРАДЫ)}[ \t]*$", текст, re.MULTILINE))
        совпадение_сообщения = ШАБЛОН_ОГРАДЫ.fullmatch(текст) if открытия else None
        if открытия > 1 or (открытия == 1 and совпадение_сообщения is None):
            raise ОшибкаКонтракта(f"messages.messages[{индекс}]: незакрытая или неоднозначная ограда {ИМЯ_ОГРАДЫ}")
        if совпадение_сообщения is not None:
            совпадения.append((индекс, совпадение_сообщения.group(1)))
    if len(совпадения) != 1:
        raise ОшибкаКонтракта(f"ChatGPT-share должен содержать ровно один блок {ИМЯ_ОГРАДЫ}; найдено {len(совпадения)}")
    индекс_сообщения, текст_пакета = совпадения[0]
    if индекс_сообщения != индекс_последнего_хода:
        raise ОшибкаКонтракта(f"ChatGPT-share: блок {ИМЯ_ОГРАДЫ} должен находиться в финальном assistant-сообщении")
    адрес_источника = документ.get("source_url")
    if not isinstance(адрес_источника, str) or re.fullmatch(r"https://chatgpt\.com/share/[A-Za-z0-9-]+", адрес_источника) is None:
        raise ОшибкаКонтракта("messages.source_url: требуется канонический https://chatgpt.com/share/<id>")
    return (текст_пакета + "\n").encode("utf-8"), адрес_источника, индекс_сообщения


def сформировать_отчёт(
    проверенный: ПроверенныйПакет,
    адрес_источника: str | None = None,
    хэш_архива_сообщений: str | None = None,
    индекс_сообщения: int | None = None,
    хэш_сырого_пакета: str | None = None,
) -> dict[str, Any]:
    отчёт: dict[str, Any] = {
        "схема": "fum.проверка-внешнего-вклада.v1",
        "статус": "проверенное_предложение",
        "идентификатор_предложения": проверенный.внешний_пакет["идентификатор_предложения"],
        "адрес_репозитория": проверенный.внешний_пакет["репозиторий"]["адрес"],
        "базовый_коммит": проверенный.внешний_пакет["репозиторий"]["базовый_коммит"],
        "хэш_sha256_канонического_пакета": проверенный.хэш_канонического_пакета,
        "хэш_sha256_патча": hashlib.sha256(проверенный.патч).hexdigest(),
        "размер_патча_в_байтах": len(проверенный.патч),
        "пути": [запись.путь for запись in проверенный.записи],
        "применено": False,
        "закоммичено": False,
        "опубликовано": False,
    }
    if адрес_источника is not None:
        отчёт["адрес_источника"] = адрес_источника
    if хэш_архива_сообщений is not None:
        отчёт["хэш_sha256_архива_сообщений"] = хэш_архива_сообщений
    if индекс_сообщения is not None:
        отчёт["индекс_сообщения"] = индекс_сообщения
    if хэш_сырого_пакета is not None:
        отчёт["хэш_sha256_сырого_пакета"] = хэш_сырого_пакета
    return отчёт


def разобрать_аргументы(аргументы_строки: Sequence[str] | None = None) -> argparse.Namespace:
    разборщик = argparse.ArgumentParser(description="Проверить пакет внешнего вклада FUM без применения к checkout.")
    подкоманды = разборщик.add_subparsers(dest="команда", required=True)
    команда_проверки = подкоманды.add_parser("проверить", help="Проверить отдельный JSON-пакет.")
    команда_проверки.add_argument("--корень-репозитория", dest="корень_репозитория", type=Path, required=True)
    команда_проверки.add_argument("--запрос", type=Path, required=True)
    команда_проверки.add_argument("--пакет", type=Path, required=True)
    команда_проверки.add_argument("--выход-патч", dest="выход_патч", type=Path)

    команда_общего_доступа = подкоманды.add_parser("проверить-share", help="Извлечь и проверить единственный пакет из архива ChatGPT-share.")
    команда_общего_доступа.add_argument("--корень-репозитория", dest="корень_репозитория", type=Path, required=True)
    команда_общего_доступа.add_argument("--запрос", type=Path, required=True)
    команда_общего_доступа.add_argument("--сообщения", type=Path, required=True)
    команда_общего_доступа.add_argument("--выход-пакет", dest="выход_пакет", type=Path)
    команда_общего_доступа.add_argument("--выход-патч", dest="выход_патч", type=Path)
    команда_общего_доступа.add_argument("--выход-проверка", dest="выход_проверка", type=Path)
    return разборщик.parse_args(аргументы_строки)


def главное(аргументы_строки: Sequence[str] | None = None) -> int:
    аргументы = разобрать_аргументы(аргументы_строки)
    try:
        адрес_источника: str | None = None
        хэш_архива_сообщений: str | None = None
        индекс_сообщения: int | None = None
        имя_сессии = проверить_путь_запроса(аргументы.корень_репозитория, аргументы.запрос)
        if аргументы.команда == "проверить":
            байты_пакета = прочитать_ограниченный_файл(аргументы.пакет, МАКСИМУМ_БАЙТОВ_ПАКЕТА, "package")
            выходной_пакет = None
            выходная_проверка = None
        else:
            ожидаемый_адрес_источника = проверить_путь_архива_сообщений(
                аргументы.корень_репозитория, аргументы.сообщения
            )
            байты_сообщений = прочитать_ограниченный_файл(аргументы.сообщения, МАКСИМУМ_БАЙТОВ_СООБЩЕНИЙ, "messages")
            хэш_архива_сообщений = hashlib.sha256(байты_сообщений).hexdigest()
            байты_пакета, адрес_источника, индекс_сообщения = извлечь_пакет_из_сообщений(байты_сообщений)
            if адрес_источника != ожидаемый_адрес_источника:
                raise ОшибкаКонтракта(
                    f"messages.source_url: {адрес_источника!r} не совпадает с архивным путём {ожидаемый_адрес_источника!r}"
                )
            if len(байты_пакета) > МАКСИМУМ_БАЙТОВ_ПАКЕТА:
                raise ОшибкаКонтракта(f"package: превышен лимит {МАКСИМУМ_БАЙТОВ_ПАКЕТА} байт")
            выходной_пакет = аргументы.выход_пакет
            выходная_проверка = аргументы.выход_проверка
        проверенный = проверить_пакет(аргументы.корень_репозитория, байты_пакета)
        отчёт = сформировать_отчёт(
            проверенный,
            адрес_источника,
            хэш_архива_сообщений,
            индекс_сообщения,
            hashlib.sha256(байты_пакета).hexdigest(),
        )
        байты_отчёта = (json.dumps(отчёт, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode(
            "utf-8"
        )
        спецификации_выходов: list[tuple[Path, bytes, str]] = []
        if выходной_пакет is not None:
            спецификации_выходов.append((выходной_пакет, проверенный.канонический_пакет, "пакет.json"))
        if аргументы.выход_патч is not None:
            спецификации_выходов.append((аргументы.выход_патч, проверенный.патч, "предложение.patch"))
        if выходная_проверка is not None:
            спецификации_выходов.append((выходная_проверка, байты_отчёта, "проверка.json"))
        подготовленные_выходы: list[tuple[Path, bytes, bool]] = []
        виденные_цели: set[Path] = set()
        for сырой_путь, данные, ожидаемое_имя in спецификации_выходов:
            цель = проверить_выходной_путь(аргументы.корень_репозитория, сырой_путь, ожидаемое_имя, имя_сессии)
            if цель in виденные_цели:
                raise ОшибкаКонтракта(f"output {цель}: один путь указан для нескольких артефактов")
            виденные_цели.add(цель)
            подготовленные_выходы.append((цель, данные, предварительно_проверить_выход(цель, данные)))
        for цель, данные, уже_существует in подготовленные_выходы:
            if not уже_существует:
                атомарно_записать_новый(цель, данные)
        print(json.dumps(отчёт, ensure_ascii=False, sort_keys=True, indent=2))
        return 0
    except (ОшибкаКонтракта, OSError) as error:
        print(f"Ошибка пакета внешнего вклада: {error}", file=sys.stderr)
        return 2



#!/usr/bin/env python3
"""Воспроизводимый выбор и восстановление иерархической очереди FUM."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from copy import deepcopy
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


СХЕМА_ОЧЕРЕДИ = "fum.иерархическая-очередь.1"
СХЕМА_ПАМЯТИ = "fum.память-очереди.1"
ПОЛИТИКА = "вектор-иерархии-1"
КЛАССЫ = {
    "обычный": 0,
    "пользовательский": 1,
    "восстановление": 2,
    "безопасность": 3,
}
СОСТОЯНИЯ = {"готов", "ожидает", "приостановлено", "заблокировано", "завершено"}
РЕЖИМЫ = {"допустима", "ручная"}
ТИПЫ_СОБЫТИЙ = {
    "добавить",
    "обновить",
    "завершить",
    "приостановить",
    "возобновить",
    "заблокировать",
}
ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ = {
    "идентификатор",
    "состояние",
    "диспетчеризация",
    "класс",
    "явный_приоритет",
    "срочность",
    "стоимость",
    "поставлен_в_очередь",
    "зависимости",
    "разблокирует",
}


class ОшибкаКонтракта(ValueError):
    """Вход нельзя безопасно отсортировать или воспроизвести."""


def _ошибка(путь: str, сообщение: str) -> ОшибкаКонтракта:
    return ОшибкаКонтракта(f"{путь}: {сообщение}")


def _целое(значение: Any, путь: str, минимум: int = 0, максимум: int = 100) -> int:
    if isinstance(значение, bool) or not isinstance(значение, int):
        raise _ошибка(путь, "ожидается целое число")
    if not минимум <= значение <= максимум:
        raise _ошибка(путь, f"ожидается диапазон {минимум}..{максимум}")
    return значение


def _строка(значение: Any, путь: str) -> str:
    if not isinstance(значение, str) or not значение.strip():
        raise _ошибка(путь, "ожидается непустая строка")
    return значение


def _момент(значение: Any, путь: str) -> datetime:
    текст = _строка(значение, путь)
    try:
        момент = datetime.fromisoformat(текст.replace("Z", "+00:00"))
    except ValueError as ошибка:
        raise _ошибка(путь, f"неверный ISO-момент: {ошибка}") from ошибка
    if момент.tzinfo is None:
        raise _ошибка(путь, "требуется смещение часового пояса")
    return момент.astimezone(timezone.utc)


def _момент_вывода(момент: datetime) -> str:
    return момент.astimezone(timezone.utc).isoformat(timespec="seconds").replace(
        "+00:00", "Z"
    )


def _список_строк(значение: Any, путь: str) -> list[str]:
    if not isinstance(значение, list) or any(
        not isinstance(элемент, str) or not элемент.strip() for элемент in значение
    ):
        raise _ошибка(путь, "ожидается список непустых строк")
    if len(set(значение)) != len(значение):
        raise _ошибка(путь, "повторяется элемент")
    return list(значение)


def _отпечаток(значение: Any) -> str:
    байты = json.dumps(
        значение,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return "sha256:" + hashlib.sha256(байты).hexdigest()


def _проверить_кандидата(сырое: Any, путь: str) -> dict[str, Any]:
    if not isinstance(сырое, dict):
        raise _ошибка(путь, "ожидается объект")
    отсутствуют = sorted(ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ - set(сырое))
    if отсутствуют:
        raise _ошибка(путь, "отсутствуют поля: " + ", ".join(отсутствуют))
    идентификатор = _строка(сырое["идентификатор"], f"{путь}.идентификатор")
    состояние = _строка(сырое["состояние"], f"{путь}.состояние")
    if состояние not in СОСТОЯНИЯ:
        raise _ошибка(f"{путь}.состояние", "неизвестное состояние")
    диспетчеризация = _строка(
        сырое["диспетчеризация"], f"{путь}.диспетчеризация"
    )
    if диспетчеризация not in РЕЖИМЫ:
        raise _ошибка(f"{путь}.диспетчеризация", "неизвестный режим")
    класс = _строка(сырое["класс"], f"{путь}.класс")
    if класс not in КЛАССЫ:
        raise _ошибка(f"{путь}.класс", "неизвестный класс")
    зависимости = _список_строк(сырое["зависимости"], f"{путь}.зависимости")
    родитель = сырое.get("родитель")
    if родитель is not None:
        родитель = _строка(родитель, f"{путь}.родитель")
    return {
        "идентификатор": идентификатор,
        "состояние": состояние,
        "диспетчеризация": диспетчеризация,
        "класс": класс,
        "явный_приоритет": _целое(
            сырое["явный_приоритет"], f"{путь}.явный_приоритет"
        ),
        "срочность": _целое(сырое["срочность"], f"{путь}.срочность"),
        "стоимость": _целое(сырое["стоимость"], f"{путь}.стоимость"),
        "поставлен_в_очередь": _строка(
            сырое["поставлен_в_очередь"], f"{путь}.поставлен_в_очередь"
        ),
        "зависимости": зависимости,
        "разблокирует": _целое(сырое["разблокирует"], f"{путь}.разблокирует"),
        **({"родитель": родитель} if родитель is not None else {}),
    }


def _эффективные_значения(
    кандидат: dict[str, Any], все: dict[str, dict[str, Any]], стек: tuple[str, ...]
) -> tuple[int, int, list[str]]:
    идентификатор = кандидат["идентификатор"]
    if идентификатор in стек:
        raise _ошибка("кандидаты", "циклическая цепочка родителей")
    класс = КЛАССЫ[кандидат["класс"]]
    приоритет = кандидат["явный_приоритет"]
    унаследовано: list[str] = []
    родитель = кандидат.get("родитель")
    if родитель in все:
        родительский_класс, родительский_приоритет, цепочка = _эффективные_значения(
            все[родитель], все, стек + (идентификатор,)
        )
        класс = max(класс, родительский_класс)
        приоритет = max(приоритет, родительский_приоритет)
        унаследовано = [родитель] + цепочка
    return класс, приоритет, унаследовано


def выбрать_очередь(вход: dict[str, Any]) -> dict[str, Any]:
    if not isinstance(вход, dict):
        raise _ошибка("вход", "ожидается объект")
    if вход.get("схема") != СХЕМА_ОЧЕРЕДИ:
        raise _ошибка("схема", f"ожидается {СХЕМА_ОЧЕРЕДИ}")
    сейчас = _момент(вход.get("сейчас"), "сейчас")
    завершённые = set(_список_строк(вход.get("завершённые", []), "завершённые"))
    сырые = вход.get("кандидаты")
    if not isinstance(сырые, list) or not сырые:
        raise _ошибка("кандидаты", "ожидается непустой список")
    кандидаты = [
        _проверить_кандидата(элемент, f"кандидаты[{номер}]")
        for номер, элемент in enumerate(сырые)
    ]
    все = {кандидат["идентификатор"]: кандидат for кандидат in кандидаты}
    if len(все) != len(кандидаты):
        raise _ошибка("кандидаты", "повторяется идентификатор")
    for номер, кандидат in enumerate(кандидаты):
        родитель = кандидат.get("родитель")
        if родитель is not None and родитель not in все and родитель not in завершённые:
            raise _ошибка(f"кандидаты[{номер}].родитель", "родитель неизвестен")
        for зависимость in кандидат["зависимости"]:
            if зависимость not in все and зависимость not in завершённые:
                raise _ошибка(
                    f"кандидаты[{номер}].зависимости", "неизвестная зависимость"
                )
        поставлен = _момент(
            кандидат["поставлен_в_очередь"],
            f"кандидаты[{номер}].поставлен_в_очередь",
        )
        if поставлен > сейчас:
            raise _ошибка(
                f"кандидаты[{номер}].поставлен_в_очередь",
                "время постановки находится в будущем",
            )
        if кандидат["состояние"] == "завершено":
            завершённые.add(кандидат["идентификатор"])
    готовые: list[dict[str, Any]] = []
    исключённые: list[dict[str, str]] = []
    for кандидат in кандидаты:
        идентификатор = кандидат["идентификатор"]
        причина: str | None = None
        if кандидат["состояние"] == "приостановлено":
            причина = "приостановлено"
        elif кандидат["состояние"] == "заблокировано":
            причина = "заблокировано"
        elif кандидат["состояние"] == "завершено":
            причина = "завершено"
        elif кандидат["диспетчеризация"] != "допустима":
            причина = "ручная диспетчеризация"
        elif кандидат["состояние"] != "готов":
            причина = "состояние не готово"
        elif not set(кандидат["зависимости"]).issubset(завершённые):
            причина = "есть незавершённые зависимости"
        if причина is not None:
            исключённые.append({"идентификатор": идентификатор, "причина": причина})
            continue
        класс, приоритет, унаследовано = _эффективные_значения(кандидат, все, ())
        возраст = int(
            (
                сейчас
                - _момент(
                    кандидат["поставлен_в_очередь"],
                    f"кандидат {идентификатор}.поставлен_в_очередь",
                )
            ).total_seconds()
            // 60
        )
        возраст = max(0, min(999999, возраст))
        вектор = [
            класс,
            приоритет,
            кандидат["разблокирует"],
            кандидат["срочность"],
            возраст,
            100 - кандидат["стоимость"],
        ]
        готовые.append(
            {
                "идентификатор": идентификатор,
                "вектор": вектор,
                "унаследовано_от": унаследовано,
                "объяснение": {
                    "класс": класс,
                    "явный_приоритет": приоритет,
                    "разблокирует": кандидат["разблокирует"],
                    "срочность": кандидат["срочность"],
                    "возраст_минут": возраст,
                    "обратная_стоимость": 100 - кандидат["стоимость"],
                },
            }
        )
    готовые.sort(key=lambda элемент: (*элемент["вектор"],), reverse=True)
    # Вектор не включает идентификатор, поэтому стабильная развязка применяется
    # отдельной группировкой, чтобы порядок не зависел от входного массива.
    начало = 0
    while начало < len(готовые):
        конец = начало + 1
        while конец < len(готовые) and готовые[конец]["вектор"] == готовые[начало]["вектор"]:
            конец += 1
        готовые[начало:конец] = sorted(
            готовые[начало:конец], key=lambda элемент: элемент["идентификатор"]
        )
        начало = конец
    тело = {
        "схема": СХЕМА_ОЧЕРЕДИ,
        "политика": ПОЛИТИКА,
        "сейчас": _момент_вывода(сейчас),
        "готовые": готовые,
        "исключённые": sorted(исключённые, key=lambda элемент: элемент["идентификатор"]),
    }
    return {**тело, "выбранный": готовые[0] if готовые else None, "отпечаток": _отпечаток(тело)}


def воспроизвести_события(вход: dict[str, Any]) -> dict[str, Any]:
    if not isinstance(вход, dict) or вход.get("схема") != СХЕМА_ПАМЯТИ:
        raise _ошибка("схема", f"ожидается {СХЕМА_ПАМЯТИ}")
    события = вход.get("события")
    if not isinstance(события, list):
        raise _ошибка("события", "ожидается список")
    состояние: dict[str, dict[str, Any]] = {}
    предыдущий_момент: datetime | None = None
    for позиция, событие in enumerate(события, 1):
        путь = f"события[{позиция - 1}]"
        if not isinstance(событие, dict):
            raise _ошибка(путь, "ожидается объект")
        if событие.get("номер") != позиция:
            raise _ошибка(f"{путь}.номер", "номер должен быть непрерывным")
        момент = _момент(событие.get("время"), f"{путь}.время")
        if предыдущий_момент is not None and момент < предыдущий_момент:
            raise _ошибка(f"{путь}.время", "время убывает")
        предыдущий_момент = момент
        тип = _строка(событие.get("тип"), f"{путь}.тип")
        if тип not in ТИПЫ_СОБЫТИЙ:
            raise _ошибка(f"{путь}.тип", "неизвестный тип")
        источник = событие.get("источник")
        if not isinstance(источник, dict):
            raise _ошибка(f"{путь}.источник", "обязателен объект происхождения")
        _строка(источник.get("задача"), f"{путь}.источник.задача")
        _строка(источник.get("сообщение"), f"{путь}.источник.сообщение")
        идентификатор = _строка(
            событие.get("идентификатор"), f"{путь}.идентификатор"
        )
        if тип == "добавить":
            if идентификатор in состояние:
                raise _ошибка(путь, "добавление повторяет идентификатор")
            состояние[идентификатор] = _проверить_кандидата(
                событие.get("кандидат"), f"{путь}.кандидат"
            )
            if состояние[идентификатор]["идентификатор"] != идентификатор:
                raise _ошибка(f"{путь}.кандидат.идентификатор", "не совпадает с событием")
            continue
        if идентификатор not in состояние:
            raise _ошибка(путь, "изменение неизвестного кандидата")
        if тип == "обновить":
            изменения = событие.get("изменения")
            if not isinstance(изменения, dict):
                raise _ошибка(f"{путь}.изменения", "ожидается объект")
            обновлённый = {**состояние[идентификатор], **изменения}
            обновлённый["идентификатор"] = идентификатор
            состояние[идентификатор] = _проверить_кандидата(обновлённый, f"{путь}.изменения")
        else:
            состояние[идентификатор]["состояние"] = {
                "завершить": "завершено",
                "приостановить": "приостановлено",
                "возобновить": "готов",
                "заблокировать": "заблокировано",
            }[тип]
    тело = {
        "схема": СХЕМА_ПАМЯТИ,
        "событий": len(события),
        "кандидаты": [состояние[идентификатор] for идентификатор in sorted(состояние)],
    }
    return {**тело, "отпечаток": _отпечаток(тело)}


def _прочитать(путь: str) -> dict[str, Any]:
    данные = sys.stdin.read() if путь == "-" else Path(путь).read_text(encoding="utf-8")
    try:
        значение = json.loads(данные)
    except json.JSONDecodeError as ошибка:
        raise _ошибка("вход", f"некорректный JSON: {ошибка}") from ошибка
    if not isinstance(значение, dict):
        raise _ошибка("вход", "корень должен быть объектом")
    return значение


def main(аргументы: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    подкоманды = parser.add_subparsers(dest="команда", required=True)
    for имя in ("выбрать", "воспроизвести"):
        подкоманда = подкоманды.add_parser(имя)
        подкоманда.add_argument("--вход", default="-", help="JSON-файл или -")
    namespace = parser.parse_args(аргументы)
    try:
        вход = _прочитать(namespace.вход)
        результат = (
            выбрать_очередь(вход)
            if namespace.команда == "выбрать"
            else воспроизвести_события(вход)
        )
    except (OSError, ОшибкаКонтракта) as ошибка:
        print(f"ошибка: {ошибка}", file=sys.stderr)
        return 2
    print(json.dumps(результат, ensure_ascii=False, sort_keys=True, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

import importlib.util
import json
import pathlib
import unittest


КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ПУТЬ = КОРЕНЬ / "scripts" / "очередь-приоритетов.py"
СПЕЦИФИКАЦИЯ = importlib.util.spec_from_file_location("очередь", ПУТЬ)
ОЧЕРЕДЬ = importlib.util.module_from_spec(СПЕЦИФИКАЦИЯ)
assert СПЕЦИФИКАЦИЯ.loader is not None
СПЕЦИФИКАЦИЯ.loader.exec_module(ОЧЕРЕДЬ)


def кандидат(
    идентификатор,
    *,
    класс="обычный",
    приоритет=0,
    срочность=0,
    стоимость=50,
    состояние="готов",
    диспетчеризация="допустима",
    поставлен="2026-09-21T18:00:00Z",
    зависимости=None,
    разблокирует=0,
    родитель=None,
):
    результат = {
        "идентификатор": идентификатор,
        "состояние": состояние,
        "диспетчеризация": диспетчеризация,
        "класс": класс,
        "явный_приоритет": приоритет,
        "срочность": срочность,
        "стоимость": стоимость,
        "поставлен_в_очередь": поставлен,
        "зависимости": [] if зависимости is None else зависимости,
        "разблокирует": разблокирует,
    }
    if родитель is not None:
        результат["родитель"] = родитель
    return результат


def очередь(*кандидаты_, завершённые=None):
    return {
        "схема": ОЧЕРЕДЬ.СХЕМА_ОЧЕРЕДИ,
        "сейчас": "2026-09-21T19:00:00Z",
        "завершённые": [] if завершённые is None else завершённые,
        "кандидаты": list(кандидаты_),
    }


class ОчередьТест(unittest.TestCase):
    def test_иерархический_порядок_и_объяснение(self):
        результат = ОЧЕРЕДЬ.выбрать_очередь(
            очередь(
                кандидат("обычный", приоритет=100),
                кандидат("безопасность", класс="безопасность", приоритет=0),
                кандидат("разблокатор", разблокирует=5),
            )
        )
        self.assertEqual(
            [элемент["идентификатор"] for элемент in результат["готовые"]],
            ["безопасность", "обычный", "разблокатор"],
        )
        self.assertEqual(результат["выбранный"]["идентификатор"], "безопасность")
        self.assertEqual(результат["политика"], "вектор-иерархии-1")

    def test_неготовые_исключаются(self):
        результат = ОЧЕРЕДЬ.выбрать_очередь(
            очередь(
                кандидат("готов"),
                кандидат("пауза", состояние="приостановлено"),
                кандидат("блок", состояние="заблокировано"),
                кандидат("ручной", диспетчеризация="ручная"),
                кандидат("ждёт", состояние="ожидает", зависимости=["готов"]),
            )
        )
        self.assertEqual([x["идентификатор"] for x in результат["готовые"]], ["готов"])
        причины = {x["идентификатор"]: x["причина"] for x in результат["исключённые"]}
        self.assertEqual(причины["пауза"], "приостановлено")
        self.assertEqual(причины["ждёт"], "состояние не готово")

    def test_зависимость_и_возраст(self):
        результат = ОЧЕРЕДЬ.выбрать_очередь(
            очередь(
                кандидат("старый", поставлен="2026-09-21T17:00:00Z"),
                кандидат("новый", поставлен="2026-09-21T18:59:00Z"),
            )
        )
        self.assertEqual(результат["готовые"][0]["идентификатор"], "старый")
        self.assertEqual(результат["готовые"][0]["объяснение"]["возраст_минут"], 120)

    def test_родитель_передаёт_приоритет(self):
        результат = ОЧЕРЕДЬ.выбрать_очередь(
            очередь(
                кандидат("родитель", класс="восстановление", приоритет=80),
                кандидат("дочь", родитель="родитель", приоритет=1),
            )
        )
        дочь = next(x for x in результат["готовые"] if x["идентификатор"] == "дочь")
        self.assertEqual(дочь["вектор"][0:2], [2, 80])
        self.assertEqual(дочь["унаследовано_от"], ["родитель"])

    def test_стабильная_развязка_не_зависит_от_входа(self):
        один = ОЧЕРЕДЬ.выбрать_очередь(очередь(кандидат("б"), кандидат("а")))
        два = ОЧЕРЕДЬ.выбрать_очередь(очередь(кандидат("а"), кандидат("б")))
        self.assertEqual(
            [x["идентификатор"] for x in один["готовые"]],
            ["а", "б"],
        )
        self.assertEqual(один["отпечаток"], два["отпечаток"])

    def test_повреждённый_вход_отклоняется(self):
        with self.assertRaises(ОЧЕРЕДЬ.ОшибкаКонтракта):
            ОЧЕРЕДЬ.выбрать_очередь(
                очередь(кандидат("а"), кандидат("а"))
            )
        with self.assertRaises(ОЧЕРЕДЬ.ОшибкаКонтракта):
            ОЧЕРЕДЬ.выбрать_очередь(
                очередь(кандидат("будущее", поставлен="2026-09-22T00:00:00Z"))
            )

    def test_журнал_событий_воспроизводится_с_происхождением(self):
        исходный = кандидат("шаг", приоритет=10)
        журнал = {
            "схема": ОЧЕРЕДЬ.СХЕМА_ПАМЯТИ,
            "события": [
                {
                    "номер": 1,
                    "время": "2026-09-21T18:00:00Z",
                    "тип": "добавить",
                    "идентификатор": "шаг",
                    "кандидат": исходный,
                    "источник": {"задача": "t-1", "сообщение": "план"},
                },
                {
                    "номер": 2,
                    "время": "2026-09-21T18:01:00Z",
                    "тип": "завершить",
                    "идентификатор": "шаг",
                    "источник": {"задача": "t-1", "сообщение": "готово"},
                },
            ],
        }
        результат = ОЧЕРЕДЬ.воспроизвести_события(журнал)
        self.assertEqual(результат["событий"], 2)
        self.assertEqual(результат["кандидаты"][0]["состояние"], "завершено")
        self.assertTrue(результат["отпечаток"].startswith("sha256:"))

    def test_журнал_без_источника_отклоняется(self):
        with self.assertRaises(ОЧЕРЕДЬ.ОшибкаКонтракта):
            ОЧЕРЕДЬ.воспроизвести_события(
                {
                    "схема": ОЧЕРЕДЬ.СХЕМА_ПАМЯТИ,
                    "события": [
                        {
                            "номер": 1,
                            "время": "2026-09-21T18:00:00Z",
                            "тип": "добавить",
                            "идентификатор": "шаг",
                            "кандидат": кандидат("шаг"),
                        }
                    ],
                }
            )


if __name__ == "__main__":
    unittest.main()

class АналитикаЗавершённыхШагов(unittest.TestCase):
    def подготовить(сам) -> None:
        временный_каталог = tempfile.TemporaryDirectory()
        сам.addCleanup(временный_каталог.cleanup)
        сам.корень = Path(временный_каталог.name) / "репозиторий"
        сам.корень.mkdir()
        сам.выполнить_гит("init", "--initial-branch=master")
        сам.выполнить_гит("config", "user.name", "FUM Tests")
        сам.выполнить_гит(
            "config",
            "user.email",
            "fum-tests@example.invalid",
        )
        (сам.корень / "README.md").write_text(
            "# Тестовый FUM\n",
            encoding="utf-8",
        )
        сам.путь_реестра = сам.корень / "реестр.json"
        сам.путь_схемы = сам.корень / "схема.json"
        сам.путь_схемы.write_bytes(
            КАНОНИЧЕСКАЯ_СХЕМА_РЕЕСТРА.read_bytes()
        )
        сам.записать_реестр(каждые=2)
        сам.зафиксировать_всё("Создать тестовый реестр")
        сам.установить_обычную_очередь()

    def выполнить_гит(
        сам,
        *аргументы: str,
        вход: str | None = None,
    ) -> subprocess.CompletedProcess[str]:
        результат = subprocess.run(
            ["git", "-C", str(сам.корень), *аргументы],
            check=False,
            capture_output=True,
            text=True,
            input=вход,
        )
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        return результат

    def выполнить(
        сам,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(СЦЕНАРИЙ), *аргументы],
            cwd=сам.корень,
            check=False,
            capture_output=True,
            text=True,
        )

    def выполнить_очередь(
        сам,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [
                sys.executable,
                str(СЦЕНАРИЙ_ОЧЕРЕДИ),
                *аргументы,
                "--repo-root",
                str(сам.корень),
                "--json",
            ],
            cwd=сам.корень,
            check=False,
            capture_output=True,
            text=True,
        )

    def загрузить_адаптер(сам, имя: str) -> object:
        спецификация = importlib.util.spec_from_file_location(имя, СЦЕНАРИЙ)
        сам.assertIsNotNone(спецификация)
        сам.assertIsNotNone(спецификация.loader)
        модуль = importlib.util.module_from_spec(спецификация)
        спецификация.loader.exec_module(модуль)
        return модуль

    def данные(
        сам,
        результат: subprocess.CompletedProcess[str],
    ) -> dict[str, object]:
        сам.assertTrue(результат.stdout.strip(), результат.stderr)
        значение = json.loads(результат.stdout)
        сам.assertIsInstance(значение, dict)
        return значение

    def записать_значение(сам, путь: Path, значение: object) -> None:
        путь.write_text(
            json.dumps(
                значение,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )

    def зафиксировать_всё(сам, сообщение: str) -> None:
        сам.выполнить_гит("add", "--", ".")
        сам.выполнить_гит("commit", "-m", сообщение)

    def идентичность_рабочей_копии(сам) -> str:
        каталог = Path(
            сам.выполнить_гит(
                "rev-parse",
                "--absolute-git-dir",
            ).stdout.strip()
        ).resolve()
        нормализованный = os.path.normcase(str(каталог))
        return hashlib.sha256(нормализованный.encode("utf-8")).hexdigest()


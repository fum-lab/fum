    def test_гонка_претензии_не_сдвигает_ветку_и_очередь(сам) -> None:
        _, исходная_вершина, поколение = (
            сам.подготовить_подтверждённую_претензию()
        )
        объект_очереди = сам.объект_ссылки(сам.ссылка_очереди())
        путь = сам.корень / "analytics-claim-cas-race.txt"
        путь.write_text("гонка specialized claim\n", encoding="utf-8")
        сам.выполнить_гит("add", "--", путь.name)
        имя_модуля = "тестируемая_очередь_гонки_claim"
        спецификация = importlib.util.spec_from_file_location(
            имя_модуля,
            СЦЕНАРИЙ_ОЧЕРЕДИ,
        )
        сам.assertIsNotNone(спецификация)
        сам.assertIsNotNone(спецификация.loader)
        модуль = importlib.util.module_from_spec(спецификация)
        sys.modules[имя_модуля] = модуль
        сам.addCleanup(sys.modules.pop, имя_модуля, None)
        спецификация.loader.exec_module(модуль)
        контекст = модуль.QueueContext(
            root=сам.корень,
            git_dir=Path(
                сам.выполнить_гит(
                    "rev-parse",
                    "--absolute-git-dir",
                ).stdout.strip()
            ),
            worktree_id=сам.идентичность_рабочей_копии(),
            queue_ref=сам.ссылка_очереди(),
            branch_ref=ССЫЛКА_ВЕТКИ,
        )
        исходный_вызов_гит = модуль.run_git
        гонка_выполнена = False

        def выполнить_гит_с_гонкой(*позиционные: object, **именованные: object) -> object:
            nonlocal гонка_выполнена
            аргументы_гит = позиционные[1] if len(позиционные) > 1 else None
            вход = именованные.get("input_bytes")
            if (
                not гонка_выполнена
                and аргументы_гит == ["update-ref", "--stdin"]
                and isinstance(вход, bytes)
                and сам.ссылка_претензии().encode("utf-8") in вход
            ):
                гонка_выполнена = True
                претензия = сам.прочитать_ссылку(сам.ссылка_претензии())
                претензия["фаза"] = "привязана"
                претензия["generation"] = None
                сам.записать_объект_в_ссылку(
                    сам.ссылка_претензии(),
                    претензия,
                )
            return исходный_вызов_гит(*позиционные, **именованные)

        with mock.patch.object(
            модуль,
            "run_git",
            side_effect=выполнить_гит_с_гонкой,
        ):
            with сам.assertRaises(модуль.QueueError):
                модуль.atomic_commit_and_handoff(
                    контекст,
                    ИДЕНТИФИКАТОР_ЗАДАЧИ,
                    поколение,
                    "Проверить CAS аналитической претензии",
                )

        сам.assertTrue(гонка_выполнена)
        сам.assertEqual(сам.вершина(), исходная_вершина)
        сам.assertEqual(сам.объект_ссылки(сам.ссылка_очереди()), объект_очереди)


    def все_строки(сам, значение: object) -> tuple[str, ...]:
        if isinstance(значение, str):
            return (значение,)
        if isinstance(значение, dict):
            строки: list[str] = []
            for ключ in sorted(значение, key=str):
                строки.extend(сам.все_строки(значение[ключ]))
            return tuple(строки)
        if isinstance(значение, list):
            строки = []
            for элемент in значение:
                строки.extend(сам.все_строки(элемент))
            return tuple(строки)
        return ()


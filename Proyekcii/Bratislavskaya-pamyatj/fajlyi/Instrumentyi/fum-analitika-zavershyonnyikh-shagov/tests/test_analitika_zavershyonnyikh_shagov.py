    def добавить_события(
        сам,
        события: list[dict[str, object]],
        конечный_номер: int,
    ) -> list[dict[str, object]]:
        дополненные = [dict(событие) for событие in события]
        for номер in range(len(дополненные) + 1, конечный_номер + 1):
            путь = сам.корень / f"результат-{номер}.txt"
            путь.write_text(f"результат {номер}\n", encoding="utf-8")
            сам.зафиксировать_всё(f"Завершить шаг {номер}")
            данные_события = {
                "branch_ref": ССЫЛКА_ВЕТКИ,
                "job_id": ИДЕНТИФИКАТОР_ИСТОЧНОГО_ЗАДАНИЯ,
                "spec_generation": номер,
                "step_id": f"master-test-step-{номер:04d}-v1",
                "card_id": f"FUM-STEP-{номер:04d}",
                "selection_head": сам.вершина(),
                "завершивший_commit": сам.вершина(),
                "результат": "commit+handoff",
            }
            основа_идентичности = {
                ключ: данные_события[ключ]
                for ключ in (
                    "branch_ref",
                    "step_id",
                    "card_id",
                    "завершивший_commit",
                    "результат",
                )
            }
            канонические_байты = json.dumps(
                основа_идентичности,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
            ).encode("utf-8")
            дополненные.append(
                {
                    "идентификатор": (
                        "sha256:"
                        + hashlib.sha256(канонические_байты).hexdigest()
                    ),
                    "номер": номер,
                    **данные_события,
                }
            )
        return дополненные


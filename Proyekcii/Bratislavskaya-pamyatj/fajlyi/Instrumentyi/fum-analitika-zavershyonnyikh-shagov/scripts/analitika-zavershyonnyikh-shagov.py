def прочитать_файл_объекта(корень: Path, сырой_путь: str, имя: str) -> dict[str, object]:
    путь = Path(сырой_путь).expanduser().resolve()
    try:
        относительный = путь.relative_to(корень)
    except ValueError as ошибка:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"{имя} находится вне рабочей копии") from ошибка
    if путь.is_symlink() or not путь.is_file():
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"{имя} не является обычным файлом")
    сырые_байты = путь.read_bytes()
    байты_из_вершины = выполнить_гит_строго(корень, f"прочитать {имя} из HEAD", "show", f"HEAD:{относительный.as_posix()}")
    if сырые_байты != байты_из_вершины:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"{имя} не совпадает с точным HEAD")
    значение = строго_разобрать_данные(сырые_байты, имя)
    return потребовать_объект(значение, имя)


def относительный_путь_файла(корень: Path, сырой_путь: str, имя: str) -> str:
    путь = Path(сырой_путь).expanduser().resolve()
    try:
        относительный = путь.relative_to(корень)
    except ValueError as ошибка:
        raise ОшибкаКонтракта(
            КОД_ОШИБКИ,
            "invalid",
            f"{имя} находится вне рабочей копии",
        ) from ошибка
    if not относительный.parts or any(
        часть in {"", ".", ".."} for часть in относительный.parts
    ):
        raise ОшибкаКонтракта(
            КОД_ОШИБКИ,
            "invalid",
            f"{имя} имеет небезопасный путь",
        )
    return относительный.as_posix()


def путь_аналитического_отчёта(
    ветка: str,
    задание: str,
    начало: int,
    конец: int,
) -> str:
    префикс = "refs/heads/"
    if not ветка.startswith(префикс):
        raise ОшибкаКонтракта(
            КОД_ОШИБКИ,
            "invalid",
            "Поддерживается только именованная локальная ветка",
        )
    части_ветки = ветка[len(префикс) :].split("/")
    if any(часть in {"", ".", ".."} for часть in части_ветки):
        raise ОшибкаКонтракта(
            КОД_ОШИБКИ,
            "invalid",
            "Ветка не образует безопасный путь отчёта",
        )
    if ШАБЛОН_ЗАДАНИЯ.fullmatch(задание) is None:
        raise ОшибкаКонтракта(
            КОД_ОШИБКИ,
            "invalid",
            "Идентификатор задания не образует безопасный путь отчёта",
        )
    return (
        Path("Оценки")
        .joinpath(
            "аналитика-завершённых-запусков",
            *части_ветки,
            задание,
            f"{начало:010d}-{конец:010d}.md",
        )
        .as_posix()
    )


def проверить_событие(корень: Path, сырое: object, ветка: str) -> dict[str, object]:
    событие = потребовать_объект(сырое, "событие завершения")
    потребовать_поля(событие, ПОЛЯ_СОБЫТИЯ, "событие завершения")
    потребовать_целое(событие["номер"], "событие.номер", 1)
    идентификатор = потребовать_строку(событие["идентификатор"], "событие.идентификатор")
    if ШАБЛОН_ХЭША.fullmatch(идентификатор) is None:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Событие имеет неверную идентичность")
    if событие["branch_ref"] != ветка:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Событие относится к другой ветке")
    for поле in ("branch_ref", "step_id", "card_id", "selection_head", "завершивший_commit", "результат", "job_id"):
        потребовать_строку(событие[поле], f"событие.{поле}")
    потребовать_целое(событие["spec_generation"], "событие.spec_generation", 1)
    if событие["результат"] != РЕЗУЛЬТАТ_СОБЫТИЯ:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Журнал содержит несчётное событие")
    if ШАБЛОН_КАРТОЧКИ.fullmatch(str(событие["card_id"])) is None:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Событие имеет неверный card_id")
    for поле in ("selection_head", "завершивший_commit"):
        if ШАБЛОН_ОБЪЕКТА.fullmatch(str(событие[поле])) is None:
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"Событие имеет неверное поле {поле}")
        проверка = выполнить_гит(корень, "cat-file", "-e", f"{событие[поле]}^{{commit}}")
        if проверка.returncode != 0:
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"Событие ссылается на неизвестный {поле}")
    основа = {
        ключ: событие[ключ]
        for ключ in ("branch_ref", "step_id", "card_id", "завершивший_commit", "результат")
    }
    ожидаемый = "sha256:" + hashlib.sha256(канонические_байты(основа).rstrip(b"\n")).hexdigest()
    if идентификатор != ожидаемый:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Идентичность события не совпадает с его устойчивыми полями")
    return dict(событие)


def прочитать_журнал(корень: Path, идентичность: str, ветка: str) -> tuple[list[dict[str, object]], str | None]:
    ссылка = ссылка_ветки(ПРОСТРАНСТВО_ЖУРНАЛОВ, идентичность, ветка)
    журнал, объект = прочитать_ссылку(корень, ссылка)
    if журнал is None:
        return [], None
    потребовать_поля(журнал, ПОЛЯ_ЖУРНАЛА, "журнал завершений")
    if журнал["схема"] != СХЕМА_ЖУРНАЛА or журнал["branch_ref"] != ветка:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Журнал имеет неверную схему или ветку")
    сырые_события = журнал["события"]
    if not isinstance(сырые_события, list) or журнал["число_событий"] != len(сырые_события):
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Число событий журнала не совпадает с массивом")
    дедуплицированные: list[dict[str, object]] = []
    по_идентификатору: dict[str, dict[str, object]] = {}
    for сырое in сырые_события:
        событие = проверить_событие(корень, сырое, ветка)
        ключ = str(событие["идентификатор"])
        прежнее = по_идентификатору.get(ключ)
        if прежнее is not None:
            if прежнее != событие:
                raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Один идентификатор события связан с разными данными")
            continue
        ожидаемый_номер = len(дедуплицированные) + 1
        if событие["номер"] != ожидаемый_номер:
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Журнал имеет разрыв порядковых номеров")
        по_идентификатору[ключ] = событие
        дедуплицированные.append(событие)
    return дедуплицированные, объект


def проверить_задание(реестр: dict[str, object], ожидаемое_задание: str, ветка: str) -> tuple[dict[str, object], int]:
    if реестр.get("branch_ref") != ветка:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Реестр относится к другой ветке")
    потребовать_строку(реестр.get("идентификатор_реестра"), "реестр.идентификатор_реестра")
    if реестр.get("версия_схемы") != 1:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Реестр имеет другую версию схемы")
    поколение_реестра = потребовать_целое(реестр.get("поколение_реестра"), "реестр.поколение_реестра", 1)
    сырые_задания = реестр.get("задания")
    if not isinstance(сырые_задания, list):
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Реестр не содержит массив заданий")
    совпадения = [потребовать_объект(сырое, "задание реестра") for сырое in сырые_задания if isinstance(сырое, dict) and сырое.get("job_id") == ожидаемое_задание]
    if len(совпадения) != 1:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Реестр должен содержать ровно одно целевое задание")
    задание = совпадения[0]
    адаптер = потребовать_объект(задание.get("адаптер"), "задание.адаптер")
    if адаптер != {"тип": ТИП_АДАПТЕРА, "контракт": КОНТРАКТ_АДАПТЕРА}:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Задание имеет другой адаптер")
    цель = потребовать_объект(задание.get("цель"), "задание.цель")
    if цель.get("branch_ref") != ветка:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Цель аналитики относится к другой ветке")
    триггер = потребовать_объект(задание.get("триггер"), "задание.триггер")
    if триггер.get("тип") != ТИП_ПОРОГА:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Аналитика должна иметь пороговый триггер")
    каждые = потребовать_целое(триггер.get("каждые"), "задание.триггер.каждые", 1)
    if триггер.get("тип_события") != "завершение_runtime_ready_commit_handoff":
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Аналитика имеет другой тип события")
    курсор = потребовать_объект(задание.get("курсор_результата"), "задание.курсор_результата")
    потребовать_поля(курсор, ПОЛЯ_КУРСОРА, "курсор результата")
    if курсор.get("тип") != ТИП_КУРСОРА:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Аналитика имеет другой курсор")
    последнее_число = потребовать_целое(
        курсор.get("последнее_число_подтверждённых_событий"),
        "задание.курсор.последнее_число_подтверждённых_событий",
        0,
    )
    следующий_порог = потребовать_целое(
        курсор.get("следующий_порог"),
        "задание.курсор.следующий_порог",
        1,
    )
    if следующий_порог != последнее_число + каждые:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Следующий порог не продолжает курсор")
    граница = потребовать_объект(курсор.get("начальная_граница"), "задание.курсор.начальная_граница")
    потребовать_поля(граница, ПОЛЯ_НАЧАЛЬНОЙ_ГРАНИЦЫ, "начальная граница")
    if (
        граница["тип"] != "версия_карточной_претензии"
        or граница["минимальная_версия_claim"] != 5
        or граница["число_событий"] != 0
    ):
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Начальная граница аналитики не доказана")
    область = потребовать_объект(курсор.get("область_анализа"), "задание.курсор.область_анализа")
    потребовать_поля(область, ПОЛЯ_ОБЛАСТИ, "область анализа")
    if (
        область["branch_ref"] != ветка
        or область["job_id"] != "master.next-step"
        or область["источник"] != ИСТОЧНИК_ОБЛАСТИ
        or область["результат"] != РЕЗУЛЬТАТ_СОБЫТИЯ
    ):
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Область анализа не совпадает с журналом")
    последний_идентификатор = курсор["последний_идентификатор_события"]
    последний_результат = курсор["последний_подтверждённый_аналитический_результат"]
    if последнее_число == 0:
        if последний_идентификатор is not None or последний_результат is not None:
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Пустой курсор содержит подтверждённый результат")
    else:
        if not isinstance(последний_идентификатор, str) or ШАБЛОН_ХЭША.fullmatch(последний_идентификатор) is None:
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Курсор имеет неверный идентификатор события")
        результат = потребовать_объект(последний_результат, "последний аналитический результат")
        потребовать_поля(результат, ПОЛЯ_АНАЛИТИЧЕСКОГО_РЕЗУЛЬТАТА, "последний аналитический результат")
        if (
            результат["конец_диапазона"] != последнее_число
            or not isinstance(результат["идентификатор"], str)
            or ШАБЛОН_ХЭША.fullmatch(результат["идентификатор"]) is None
            or not isinstance(результат["путь"], str)
            or not результат["путь"]
            or not isinstance(результат["content_sha256"], str)
            or ШАБЛОН_ХЭША.fullmatch(результат["content_sha256"]) is None
        ):
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Последний аналитический результат не совпадает с курсором")
    поколение = потребовать_целое(задание.get("поколение"), "задание.поколение", 1)
    return задание, поколение_реестра


def вычислить_ключ_запуска(задание: str, поколение: int, наступление: dict[str, object]) -> str:
    вход = {"job_id": задание, "spec_generation": поколение, "trigger_occurrence": наступление}
    return "sha256:" + hashlib.sha256(канонические_байты(вход).rstrip(b"\n")).hexdigest()


def построить_показ(корень: Path, ветка: str, идентичность: str, путь_реестра: str, путь_схемы: str, задание: str) -> dict[str, object]:
    реестр = прочитать_файл_объекта(корень, путь_реестра, "реестр")
    прочитать_файл_объекта(корень, путь_схемы, "схема реестра")
    описание, поколение_реестра = проверить_задание(реестр, задание, ветка)
    события, _ = прочитать_журнал(корень, идентичность, ветка)
    курсор = потребовать_объект(описание["курсор_результата"], "курсор")
    область = потребовать_объект(курсор["область_анализа"], "область")
    отобранные = [событие for событие in события if событие["branch_ref"] == область["branch_ref"] and событие["job_id"] == область["job_id"] and событие["результат"] == область["результат"]]
    последнее_число_курсора = int(
        курсор["последнее_число_подтверждённых_событий"]
    )
    последний_идентификатор_курсора = курсор[
        "последний_идентификатор_события"
    ]
    if последнее_число_курсора > len(отобранные):
        raise ОшибкаКонтракта(
            КОД_ОШИБКИ,
            "invalid",
            "Курсор аналитики находится впереди подтверждённого журнала",
        )
    if последнее_число_курсора == 0:
        if последний_идентификатор_курсора is not None:
            raise ОшибкаКонтракта(
                КОД_ОШИБКИ,
                "invalid",
                "Нулевой курсор аналитики содержит последнее событие",
            )
    elif (
        отобранные[последнее_число_курсора - 1]["идентификатор"]
        != последний_идентификатор_курсора
    ):
        raise ОшибкаКонтракта(
            КОД_ОШИБКИ,
            "invalid",
            "Последнее событие курсора не совпадает с подтверждённым журналом",
        )
    основа = {
        "state": "not_ready",
        "status": str(описание.get("состояние", "invalid")),
        "branch_ref": ветка,
        "selection_head": вершина_ветки(корень, ветка),
        "job_id": задание,
        "spec_generation": описание["поколение"],
        "поколение_реестра": поколение_реестра,
        "идентификатор_реестра": реестр.get("идентификатор_реестра"),
        "версия_схемы_реестра": реестр.get("версия_схемы"),
        "хэш_реестра": "sha256:"
        + hashlib.sha256(
            канонические_байты(реестр).rstrip(b"\n")
        ).hexdigest(),
        "число_подтверждённых_событий": len(отобранные),
        "последний_идентификатор_события": отобранные[-1]["идентификатор"] if отобранные else None,
        "последнее_число_курсора": курсор[
            "последнее_число_подтверждённых_событий"
        ],
        "последний_подтверждённый_аналитический_результат": курсор[
            "последний_подтверждённый_аналитический_результат"
        ],
        "курсор_до": copy.deepcopy(курсор),
    }
    if описание.get("состояние") != "active":
        return основа
    порог = int(курсор["следующий_порог"])
    if len(отобранные) < порог:
        основа["status"] = "ожидание_порога"
        return основа
    триггер = потребовать_объект(описание["триггер"], "триггер")
    начало = порог - int(триггер["каждые"]) + 1
    диапазон = [событие for событие in отобранные if начало <= int(событие["номер"]) <= порог]
    if len(диапазон) != порог - начало + 1:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Конечный диапазон порога неполон")
    наступление = {"тип": ТИП_ПОРОГА, "тип_события": триггер["тип_события"], "начало": начало, "конец": порог}
    основа.update(
        {
            "state": "ready",
            "status": "ready",
            "порог": порог,
            "trigger_occurrence": наступление,
            "run_key": вычислить_ключ_запуска(задание, int(описание["поколение"]), наступление),
            "диапазон_событий": {
                "начало": начало,
                "конец": порог,
                "идентификаторы_событий": [событие["идентификатор"] for событие in диапазон],
                "источники": диапазон,
            },
        }
    )
    return основа


def проверить_ожидания(показ: dict[str, object], аргументы: argparse.Namespace) -> None:
    пары = (
        ("branch_ref", аргументы.ожидаемая_ветка),
        ("selection_head", аргументы.ожидаемая_вершина),
        ("job_id", аргументы.ожидаемое_задание),
        ("spec_generation", аргументы.ожидаемое_поколение),
        ("поколение_реестра", аргументы.ожидаемое_поколение_реестра),
        ("run_key", аргументы.ожидаемый_ключ),
        ("порог", аргументы.ожидаемый_порог),
    )
    if показ.get("state") != "ready" or any(показ.get(поле) != ожидаемое for поле, ожидаемое in пары):
        raise ОшибкаКонтракта(КОД_НЕСОВПАДЕНИЯ, "mismatch", "Точное наступление порога изменилось")


def проверить_претензию(сырая: object) -> dict[str, object]:
    претензия = потребовать_объект(сырая, "претензия")
    потребовать_поля(претензия, ПОЛЯ_ПРЕТЕНЗИИ, "претензия")
    фаза = претензия["фаза"]
    if претензия["схема"] != СХЕМА_ПРЕТЕНЗИИ or фаза not in {
        "зарезервирована",
        "привязана",
        "подтверждена",
        "очищена",
        "передана",
        "завершена",
    }:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Претензия имеет неверную схему или фазу")
    for поле in (
        "branch_ref",
        "selection_head",
        "job_id",
        "run_key",
        "идентификатор_попытки",
        "lease_id",
        "назначение",
        "путь_реестра",
        "путь_отчёта",
        "идентификатор_анализа",
    ):
        потребовать_строку(претензия[поле], f"претензия.{поле}")
    for поле in ("selection_head",):
        if ШАБЛОН_ОБЪЕКТА.fullmatch(str(претензия[поле])) is None:
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"Претензия имеет неверное поле {поле}")
    for поле in ("run_key", "идентификатор_анализа"):
        if ШАБЛОН_ХЭША.fullmatch(str(претензия[поле])) is None:
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"Претензия имеет неверное поле {поле}")
    for поле in ("идентификатор_попытки", "lease_id"):
        try:
            if str(uuid.UUID(str(претензия[поле]))) != претензия[поле]:
                raise ValueError
        except ValueError as ошибка:
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"Претензия имеет неверное поле {поле}") from ошибка
    потребовать_целое(претензия["spec_generation"], "претензия.spec_generation", 1)
    потребовать_целое(претензия["поколение_реестра"], "претензия.поколение_реестра", 1)
    порог = потребовать_целое(претензия["порог"], "претензия.порог", 1)
    наступление = потребовать_объект(претензия["trigger_occurrence"], "наступление претензии")
    потребовать_поля(наступление, ПОЛЯ_НАСТУПЛЕНИЯ, "наступление претензии")
    диапазон = потребовать_объект(претензия["диапазон_событий"], "диапазон претензии")
    потребовать_поля(диапазон, ПОЛЯ_ДИАПАЗОНА, "диапазон претензии")
    начало = потребовать_целое(диапазон["начало"], "диапазон.начало", 1)
    конец = потребовать_целое(диапазон["конец"], "диапазон.конец", начало)
    идентификаторы = диапазон["идентификаторы_событий"]
    источники = диапазон["источники"]
    if (
        конец != порог
        or наступление != {
            "тип": ТИП_ПОРОГА,
            "тип_события": "завершение_runtime_ready_commit_handoff",
            "начало": начало,
            "конец": конец,
        }
        or not isinstance(идентификаторы, list)
        or not isinstance(источники, list)
        or len(идентификаторы) != конец - начало + 1
        or len(источники) != len(идентификаторы)
        or any(
            not isinstance(идентификатор, str)
            or ШАБЛОН_ХЭША.fullmatch(идентификатор) is None
            for идентификатор in идентификаторы
        )
        or any(
            not isinstance(источник, dict)
            or источник.get("идентификатор") != идентификатор
            for источник, идентификатор in zip(источники, идентификаторы)
        )
    ):
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Претензия имеет неверный конечный диапазон")
    for поле in ("путь_реестра", "путь_отчёта"):
        путь = Path(str(претензия[поле]))
        if путь.is_absolute() or any(часть in {"", ".", ".."} for часть in путь.parts):
            raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", f"Претензия имеет небезопасный {поле}")
    ожидаемый_путь = путь_аналитического_отчёта(
        str(претензия["branch_ref"]),
        str(претензия["job_id"]),
        начало,
        конец,
    )
    if претензия["путь_отчёта"] != ожидаемый_путь:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Претензия имеет недетерминированный путь отчёта")
    if претензия["идентификатор_анализа"] != вычислить_идентификатор_анализа(претензия):
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Идентификатор анализа не воспроизводится из диапазона")
    if претензия["run_key"] != вычислить_ключ_запуска(
        str(претензия["job_id"]),
        int(претензия["spec_generation"]),
        наступление,
    ):
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Ключ запуска претензии не воспроизводится")
    идентификатор_задачи_претензии = претензия["task_id"]
    поколение_претензии = претензия["generation"]
    свидетельство = претензия["свидетельство_передачи"]
    результат = претензия["подтверждённый_результат"]
    if фаза == "зарезервирована":
        допустимо = идентификатор_задачи_претензии is None and поколение_претензии is None and свидетельство is None and результат is None
    elif фаза == "привязана":
        допустимо = isinstance(идентификатор_задачи_претензии, str) and bool(идентификатор_задачи_претензии) and поколение_претензии is None and свидетельство is None and результат is None
    elif фаза == "подтверждена":
        допустимо = isinstance(идентификатор_задачи_претензии, str) and bool(идентификатор_задачи_претензии) and isinstance(поколение_претензии, str) and bool(поколение_претензии) and свидетельство is None and результат is None
    elif фаза == "очищена":
        допустимо = (
            isinstance(идентификатор_задачи_претензии, str)
            and bool(идентификатор_задачи_претензии)
            and isinstance(поколение_претензии, str)
            and bool(поколение_претензии)
            and isinstance(свидетельство, dict)
            and результат is None
        )
        if isinstance(свидетельство, dict):
            потребовать_поля(
                свидетельство,
                ПОЛЯ_СВИДЕТЕЛЬСТВА_ЧИСТОГО_ЗАВЕРШЕНИЯ,
                "свидетельство чистого завершения",
            )
            if (
                свидетельство["task_id"] != идентификатор_задачи_претензии
                or свидетельство["generation"] != поколение_претензии
                or not isinstance(свидетельство["base_head"], str)
                or ШАБЛОН_ОБЪЕКТА.fullmatch(str(свидетельство["base_head"])) is None
            ):
                допустимо = False
    else:
        допустимо = (
            isinstance(идентификатор_задачи_претензии, str)
            and bool(идентификатор_задачи_претензии)
            and isinstance(поколение_претензии, str)
            and bool(поколение_претензии)
            and isinstance(свидетельство, dict)
        )
        if isinstance(свидетельство, dict):
            потребовать_поля(
                свидетельство,
                ПОЛЯ_СВИДЕТЕЛЬСТВА_ПЕРЕДАЧИ,
                "свидетельство передачи",
            )
            if (
                свидетельство["base_head"] != претензия["selection_head"]
                or свидетельство["task_id"] != идентификатор_задачи_претензии
                or свидетельство["generation"] != поколение_претензии
                or not isinstance(свидетельство["commit"], str)
                or ШАБЛОН_ОБЪЕКТА.fullmatch(str(свидетельство["commit"])) is None
            ):
                допустимо = False
        if фаза == "передана":
            допустимо = допустимо and результат is None
        elif isinstance(результат, dict):
            потребовать_поля(результат, ПОЛЯ_ПОДТВЕРЖДЁННОГО_РЕЗУЛЬТАТА, "подтверждённый результат")
            if (
                результат["идентификатор"] != претензия["идентификатор_анализа"]
                or результат["путь"] != претензия["путь_отчёта"]
                or результат["конец_диапазона"] != конец
                or not isinstance(результат["content_sha256"], str)
                or ШАБЛОН_ХЭША.fullmatch(результат["content_sha256"]) is None
                or not isinstance(результат["commit"], str)
                or ШАБЛОН_ОБЪЕКТА.fullmatch(результат["commit"]) is None
                or not isinstance(свидетельство, dict)
                or результат["commit"] != свидетельство["commit"]
            ):
                допустимо = False
        else:
            допустимо = False
    if not допустимо:
        raise ОшибкаКонтракта(КОД_ОШИБКИ, "invalid", "Фаза претензии не совпадает с владением и результатом")
    return претензия


def совпадает_претензия(претензия: dict[str, object], показ: dict[str, object], попытка: str, аренда: str) -> bool:
    return all(
        (
            претензия["branch_ref"] == показ["branch_ref"],
            претензия["selection_head"] == показ["selection_head"],
            претензия["job_id"] == показ["job_id"],
            претензия["spec_generation"] == показ["spec_generation"],
            претензия["поколение_реестра"] == показ["поколение_реестра"],
            претензия["trigger_occurrence"] == показ["trigger_occurrence"],
            претензия["run_key"] == показ["run_key"],
            претензия["порог"] == показ["порог"],
            претензия["идентификатор_попытки"] == попытка,
            претензия["lease_id"] == аренда,
        )
    )



def вывести(значение: dict[str, object]) -> None:
    print(json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":")))


def главная(аргументы: list[str] | None = None) -> int:
    разобранные = построить_парсер().parse_args(аргументы)
    try:
        if разобранные.команда == "наблюдать":
            корень, ветка, идентичность = разрешить_контекст(разобранные.корень)
            if ветка != разобранные.ожидаемая_ветка:
                raise ОшибкаКонтракта(КОД_НЕСОВПАДЕНИЯ, "mismatch", "Ветка наблюдения изменилась")
            события, _ = прочитать_журнал(корень, идентичность, ветка)
            результат = {"state": "observed", "branch_ref": ветка, "число_подтверждённых_событий": len(события), "последний_идентификатор_события": события[-1]["идентификатор"] if события else None}
        elif разобранные.команда == "показать":
            корень, ветка, идентичность = разрешить_контекст(разобранные.корень)
            результат = построить_показ(корень, ветка, идентичность, разобранные.реестр, разобранные.схема, разобранные.ожидаемое_задание)
        elif разобранные.команда == "претендовать":
            результат = претендовать(разобранные)
        elif разобранные.команда == "освободить":
            результат = освободить(разобранные)
        elif разобранные.команда == "bind-run":
            результат = привязать(разобранные, False)
        elif разобранные.команда == "verify-run":
            результат = привязать(разобранные, True)
        else:
            результат = завершить(разобранные)
    except ОшибкаКонтракта as ошибка:
        вывести({"state": ошибка.состояние, "error": str(ошибка)})
        return ошибка.код
    вывести(результат)
    return 0


if __name__ == "__main__":
    raise SystemExit(главная())

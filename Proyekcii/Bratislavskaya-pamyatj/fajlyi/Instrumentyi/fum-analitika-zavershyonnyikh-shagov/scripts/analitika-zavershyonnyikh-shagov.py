def вычислить_идентификатор_анализа(показ: dict[str, object]) -> str:
    диапазон = потребовать_объект(показ["диапазон_событий"], "диапазон")
    вход = {
        "branch_ref": показ["branch_ref"],
        "job_id": показ["job_id"],
        "spec_generation": показ["spec_generation"],
        "trigger_occurrence": показ["trigger_occurrence"],
        "начало": диапазон["начало"],
        "конец": диапазон["конец"],
        "идентификаторы_событий": диапазон["идентификаторы_событий"],
    }
    return "sha256:" + hashlib.sha256(
        канонические_байты(вход).rstrip(b"\n")
    ).hexdigest()



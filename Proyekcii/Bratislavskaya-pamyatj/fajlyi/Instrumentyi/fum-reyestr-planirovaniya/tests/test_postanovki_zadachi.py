"""Точная база постановки и сохранённое наблюдение до первой записи."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import unittest

from test_входа_направления import открытый_вход, ЗАДАЧА, строка

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import постановка_задачи as постановка


def гит(корень, *аргументы):
    return subprocess.check_output(["git", *аргументы], cwd=корень).decode().strip()


def манифест(корень):
    return {"коммит": гит(корень, "rev-parse", "HEAD"), "ветка": гит(корень, "symbolic-ref", "HEAD"), "файлы": {"README.md": hashlib.sha256((корень / "README.md").read_bytes()).hexdigest()}}


def нативный_источник(корень, источник, коммит):
    источник.write_bytes(строка({"type": "session_meta", "payload": {"id": ЗАДАЧА, "cwd": str(корень), "git": {"commit_hash": коммит}}}) + строка({"type": "turn_context", "payload": {"cwd": str(корень), "model": "gpt-6-astra", "effort": "ultra"}}))


class ПроверкаПостановки(unittest.TestCase):
    def test_постановка_задаёт_явную_существующую_ветку(проверка):
        with открытый_вход() as (корень, источник, решение):
            запись = манифест(корень)
            гит(корень, "branch", "master")
            результат = постановка.проверить_постановку(корень, запись)
            проверка.assertEqual({"type": "branch", "branchName": запись["ветка"]}, результат["startingState"])
            проверка.assertEqual(запись["коммит"], результат["коммит"])

    def test_неизвестный_коммит_и_отсутствующий_файл_закрывают_допуск(проверка):
        with открытый_вход() as (корень, источник, решение):
            for изменение in ({"коммит": "f" * 40}, {"файлы": {}}, {"файлы": {"постановка.md": "a" * 64}}):
                with проверка.subTest(изменение=изменение), проверка.assertRaises(постановка.ОшибкаПриёма):
                    постановка.проверить_постановку(корень, {**манифест(корень), **изменение})

    def test_сдвиг_ветки_не_подменяет_полный_коммит(проверка):
        with открытый_вход() as (корень, источник, решение):
            запись = манифест(корень)
            гит(корень, "-c", "user.name=Фикстура", "-c", "user.email=fixture@example.invalid", "commit", "--allow-empty", "-qm", "Сдвиг")
            with проверка.assertRaises(постановка.ОшибкаПриёма):
                постановка.проверить_постановку(корень, запись)

    def test_первичное_наблюдение_сохраняется_до_записи_и_проверяется_позже(проверка):
        with открытый_вход() as (корень, источник, решение):
            запись = манифест(корень)
            нативный_источник(корень, источник, запись["коммит"])
            первый = постановка.подтвердить_начало(корень, ЗАДАЧА, запись["коммит"], источник)
            (корень / "результат.md").write_text("Первый результат")
            гит(корень, "add", ".")
            гит(корень, "commit", "-qm", "Работа после проверки")
            прочитанный = постановка.прочитать_подтверждение(корень, ЗАДАЧА, запись["коммит"], источник)
            проверка.assertEqual(первый, прочитанный)
            проверка.assertEqual(запись["коммит"], прочитанный["начальный_HEAD"])
            проверка.assertNotEqual(гит(корень, "rev-parse", "HEAD"), прочитанный["начальный_HEAD"])

    def test_поздняя_вершина_без_раннего_подтверждения_не_принимается(проверка):
        with открытый_вход() as (корень, источник, решение):
            запись = манифест(корень)
            нативный_источник(корень, источник, запись["коммит"])
            гит(корень, "commit", "--allow-empty", "-qm", "Уже началась работа")
            with проверка.assertRaises(постановка.ОшибкаПриёма):
                постановка.подтвердить_начало(корень, ЗАДАЧА, запись["коммит"], источник)

    def test_иная_начальная_база_либо_модель_не_подтверждаются(проверка):
        with открытый_вход() as (корень, источник, решение):
            запись = манифест(корень)
            нативный_источник(корень, источник, "f" * 40)
            with проверка.assertRaises(постановка.ОшибкаПриёма):
                постановка.подтвердить_начало(корень, ЗАДАЧА, запись["коммит"], источник)
            нативный_источник(корень, источник, запись["коммит"])
            источник.write_bytes(источник.read_bytes().replace(b'ultra', b'medium'))
            with проверка.assertRaises(постановка.ОшибкаПриёма):
                постановка.подтвердить_начало(корень, ЗАДАЧА, запись["коммит"], источник)


if __name__ == "__main__":
    unittest.main()

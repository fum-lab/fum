    def test_старый_подготовить_закрывается_после_появления_намерения(проверка):
        with неготовый_приём() as (корень, источник, решение, запрос, карточки, исполнитель, исходная, исправление):
            применить = исполнитель.хранилище.применить_файлы
            установить = исполнение.хранилище.установить
            def только_намерение(путь, данные):
                установить(путь, данные)
                if путь == исполнитель.хранилище.путь and 'fum.исполнение-приёма.2'.encode() in данные:
                    raise OSError("Остановить после намерения")
            def исправление_между_чтением_и_замком(*аргументы, **параметры):
                with mock.patch.object(исполнение.хранилище, "установить", side_effect=только_намерение):
                    with проверка.assertRaises(OSError):
                        исполнитель.исправить_план(исправление)
                return применить(*аргументы, **параметры)
            with mock.patch.object(исполнитель.хранилище, "применить_файлы", side_effect=исправление_между_чтением_и_замком):
                with проверка.assertRaisesRegex(исполнение.ОшибкаПриёма, "исправить-план"):
                    исполнитель.подготовить(источник, ЗАДАЧА, решение, запрос, карточки)
            проверка.assertEqual(исходная["файлы"], {имя: (корень / имя).read_text() for имя in исходная["файлы"]})

    def test_попытка_между_двумя_замками_исправления_не_допускает_эффект(проверка):
        with неготовый_приём() as (корень, источник, решение, запрос, карточки, исполнитель, исходная, исправление):
            изменить = исполнитель.хранилище.изменить
            добавлена = False
            @contextmanager
            def вмешаться():
                nonlocal добавлена
                нужна = False
                with изменить() as состояние:
                    yield состояние
                    нужна = not добавлена and any(этап["этап"].startswith("исправление карточек ") and not этап["готов"] for этап in состояние["этапы"].values())
                if нужна:
                    добавлена = True
                    исполнитель.хранилище.начать_попытку(исправление["событие"], {"поручение": "Внешний эффект между замками"})
            with mock.patch.object(исполнитель.хранилище, "изменить", side_effect=вмешаться):
                with проверка.assertRaisesRegex(исполнение.ОшибкаПриёма, "попытки"):
                    исполнитель.исправить_план(исправление)
            проверка.assertTrue(добавлена)
            проверка.assertEqual(исходная["файлы"], {имя: (корень / имя).read_text() for имя in исходная["файлы"]})

    def test_новая_явная_база_и_эффективные_карточки_проверяются_до_допуска(проверка):
        with неготовый_приём(с_индексом=True) as (корень, источник, решение, запрос, карточки, исполнитель, исходная, исправление):
            (корень / "README.md").write_text("Новый принятый код восстановления")
            исполнение.хранилище.гит(корень, "add", "README.md")
            исполнение.хранилище.гит(корень, "commit", "-qm", "Этап восстановления")
            исправление["база"] = исполнение.хранилище.гит(корень, "rev-parse", "HEAD").strip()
            результат = исполнитель.исправить_план(исправление)
            исполнение.хранилище.гит(корень, "add", ".")
            исполнение.хранилище.гит(корень, "commit", "-qm", "Исправленная постановка")
            коммит = исполнение.хранилище.гит(корень, "rev-parse", "HEAD").strip()
            with mock.patch.object(исполнение, "проверить_инструменты"):
                исполнитель.закрепить_постановку(результат["событие"], коммит, исправление["ветка"])
                имя = исправление["файлы"][0]["путь"]
                (корень / имя).write_text(исходная["файлы"][имя])
                with проверка.assertRaises(исполнение.ОшибкаПриёма):
                    исполнитель.допустить_вызов(источник, ЗАДАЧА, решение)
                (корень / имя).write_text(исправление["файлы"][0]["содержимое"])
                первый = исполнитель.допустить_вызов(источник, ЗАДАЧА, решение)
                проверка.assertTrue(первый["разрешён_вызов"])
                следующий = {"тип": "шаг", "операция": "создать", "имя": "следующий-план", "заголовок": "Следующий план",
                             "содержимое": "## Задача\n\nСоставить следующий план.\n\n## Почему сейчас\n\nПринято следующее направление.\n\n## Критерии завершения\n\n- План проверен.\n"}
                новые = исполнение.вход.подготовить_карточки(корень, [следующий], {"FUM-STEP": "FUM-STEP-0006"}, запрос)
                for путь, содержимое in новые.items():
                    (корень / путь).write_text(содержимое)
                исполнение.проверить_планирование(корень)
                повтор = исполнитель.допустить_вызов(источник, ЗАДАЧА, решение)
                проверка.assertFalse(повтор["разрешён_вызов"])
                проверка.assertEqual(первый["попытка"], повтор["попытка"])

    def test_реальная_обратная_пара_исправляется_без_замены_исходного_намерения(проверка):
        with неготовый_приём() as (корень, источник, решение, запрос, карточки, исполнитель, исходная, исправление):
            результат = исполнитель.исправить_план(исправление)
            проверка.assertTrue(результат["готов"])
            исполнение.проверить_планирование(корень)
            with исполнитель.хранилище.изменить() as состояние:
                запись = состояние["приёмы"][исправление["событие"]]
                for поле in ("карточки", "файлы", "свидетельства", "номера", "решение", "база"):
                    проверка.assertEqual(исходная[поле], запись[поле])
                проверка.assertIn("missing inverse semantic relation", запись["исправление"]["исходный_отказ"])
            до = исполнитель.хранилище.путь.read_bytes()
            проверка.assertEqual(результат, отдельный_процесс(корень, исправление))
            проверка.assertEqual(до, исполнитель.хранилище.путь.read_bytes())

    def test_новый_процесс_продолжает_после_намерения_и_после_карточечного_эффекта(проверка):
        for фаза in ("намерение", "карточка", "реестр"):
            with проверка.subTest(фаза=фаза), неготовый_приём() as (корень, источник, решение, запрос, карточки, исполнитель, исходная, исправление):
                установить = исполнение.хранилище.установить
                цель = корень / исправление["файлы"][0]["путь"]
                прервано = False
                def оборвать(путь, данные):
                    nonlocal прервано
                    установить(путь, данные)
                    намерение = путь == исполнитель.хранилище.путь and b'fum.' in данные and 'fum.исполнение-приёма.2'.encode() in данные
                    если = (фаза == "намерение" and намерение or фаза == "карточка" and путь == цель
                            or фаза == "реестр" and путь == корень / исполнение.ПУТЬ_РЕЕСТРА)
                    if если and not прервано:
                        прервано = True
                        raise OSError("Наблюдаемый сбой после долговечной установки")
                with mock.patch.object(исполнение.хранилище, "установить", side_effect=оборвать), проверка.assertRaises(OSError):
                    исполнитель.исправить_план(исправление)
                проверка.assertTrue(прервано)
                with проверка.assertRaisesRegex(исполнение.ОшибкаПриёма, "исправить-план"):
                    исполнитель.подготовить(источник, ЗАДАЧА, решение, запрос, карточки)
                результат = отдельный_процесс(корень, исправление)
                проверка.assertTrue(результат["готов"])
                проверка.assertEqual(исправление["файлы"][0]["содержимое"], цель.read_text())
                исполнение.проверить_планирование(корень)

    def test_точные_границы_запрещают_подмену_до_эффектов(проверка):
        for вид in ("план", "хэш", "база", "ветка", "номер", "статус", "заголовок", "путь", "чужое", "попытка"):
            with проверка.subTest(вид=вид), неготовый_приём() as (корень, источник, решение, запрос, карточки, исполнитель, исходная, исправление):
                if вид == "план": исправление["ожидаемый_план_sha256"] = "0" * 64
                if вид == "хэш": исправление["файлы"][0]["ожидаемый_sha256"] = "0" * 64
                if вид == "база": исправление["база"] = "0" * 40
                if вид == "ветка": исправление["ветка"] = "refs/heads/codex/другая"
                if вид == "номер": исправление["файлы"][0]["содержимое"] = исправление["файлы"][0]["содержимое"].replace("FUM-REQ-0001", "FUM-REQ-9999")
                if вид == "статус": исправление["файлы"][0]["содержимое"] = исправление["файлы"][0]["содержимое"].replace("— `🟡`", "— `🚧`")
                if вид == "заголовок": исправление["файлы"][0]["содержимое"] = исправление["файлы"][0]["содержимое"].replace("# Сохранять трассу", "# Иное название")
                if вид == "путь": исправление["файлы"][0]["путь"] = запрос
                if вид == "чужое": (корень / карточки[1]["путь"]).write_text("Чужое изменение")
                if вид == "попытка": исполнитель.хранилище.начать_попытку(исправление["событие"], {"поручение": "Внешняя попытка без ответа"})
                до = {имя: (корень / имя).read_bytes() for имя in исходная["файлы"]}
                with проверка.assertRaises(исполнение.ОшибкаПриёма):
                    исполнитель.исправить_план(исправление)
                проверка.assertEqual(до, {имя: (корень / имя).read_bytes() for имя in исходная["файлы"]})



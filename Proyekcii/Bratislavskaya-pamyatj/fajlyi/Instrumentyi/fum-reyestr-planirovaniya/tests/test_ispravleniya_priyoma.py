        строка = "Статус требования — `🟡`.\n\n"
        for заголовок in ("Статус и границы\n----------------", "Статус и\nграницы\n-",
                           "**Статус и границы**\n   -- \t", "Статус и границы\n="):
            with проверка.subTest(заголовок=заголовок):
                до = пример["содержимое"].replace("## Источники требований\n\n",
                    "## Источники требований\n\n" + заголовок + "\n\nСтатус требования — `✅`.\n\n", 1)
                проверка.assertIn(заголовок, до)

            гит(сам.ф.цель, "commit", "-m", "Доставить базу")
            сам.assertEqual(доставка.подтвердить_коммит()["стадия"], "закоммичено")
            сам.assertEqual(доставка.подтвердить_получение("Проверена работоспособность ветки")["получатель"], "подтверждено")
            сам.assertIsNone(доставка.состояние()["публикация"])


def гит(корень, *аргументы):
    среда = {ключ: значение for ключ, значение in os.environ.items() if not ключ.startswith("GIT_")}
    среда.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull,
                GIT_AUTHOR_NAME="Открытая фикстура", GIT_AUTHOR_EMAIL="fixture@example.invalid",
                GIT_COMMITTER_NAME="Открытая фикстура", GIT_COMMITTER_EMAIL="fixture@example.invalid")
    return subprocess.run(["git", "-c", "commit.gpgSign=false", *аргументы], cwd=корень,
                          env=среда, capture_output=True, check=True).stdout.decode().strip()


class Фикстура:
    def __init__(сам, папка):
        сам.папка = Path(папка).resolve()
        сам.источник = сам.папка / "источник"
        сам.цель = сам.папка / "получатель"
        сам.источник.mkdir()
        гит(сам.источник, "init", "-b", "codex/источник")
        гит(сам.источник, "config", "user.name", "Открытая фикстура")
        гит(сам.источник, "config", "user.email", "fixture@example.invalid")
        сам.записать(сам.источник, "основа.txt", "основа\n")
        сам.записать(сам.источник, ".gitignore", "*.private\n")
        сам.база = сам.коммит(сам.источник)
        гит(сам.источник, "worktree", "add", "-b", "codex/получатель", str(сам.цель))
        сам.записать(сам.источник, "обновление.txt", "обновление\n")
        сам.срез = сам.коммит(сам.источник)
        сам.записать(сам.цель, "работа.txt", "работа\n")
        сам.вершина = сам.коммит(сам.цель)
        сам.владельцы = {str(сам.цель): {"задача": ЗАДАЧА, "ref": "refs/heads/codex/получатель"}}
        сам.реестр = сам.папка / "владельцы.json"
        сам.реестр.write_bytes(байты(сам.владельцы))
        сам.описание = сам.принять(сам.срез)

    def записать(сам, корень, имя, текст):
        (корень / имя).write_text(текст)

    def коммит(сам, корень):
        гит(корень, "add", ".")
        гит(корень, "commit", "-m", "Открытое изменение")
        return гит(корень, "rev-parse", "HEAD")

    def принять(сам, срез, состояние="принят промежуточный срез"):
        решение = {"схема": "fum.решение-приёмки-среза.1", "коммит": срез,
                   "дерево": гит(сам.источник, "rev-parse", срез + "^{tree}"),
                   "проверяющий": КООРДИНАТОР, "состояние": состояние,
                   "граница": "Открытая фикстура; проверена только читаемость файла",
                   "свидетельства": [{"путь": "основа.txt", "sha256": hashlib.sha256((сам.источник / "основа.txt").read_bytes()).hexdigest()}]}
        сам.записать(сам.источник, "приёмка.json", байты(решение).decode())
        свидетельство = сам.коммит(сам.источник)
        return {"корень": str(сам.источник), "ref": "refs/heads/codex/источник", "коммит": свидетельство,
                "владелец": КООРДИНАТОР, "срез": срез,
                "приёмка": {"путь": "приёмка.json", "sha256": hashlib.sha256(байты(решение)).hexdigest()}}

    def план(сам):
        return построить_план(сам.описание, [str(сам.цель)], сам.владельцы)

    def владелец(сам, план=None, каталог=None, задача=ЗАДАЧА):
        прежний = Path.cwd()
        os.chdir(сам.цель)
        try:
            with patch.dict(os.environ, {"CODEX_THREAD_ID": задача}):
                yield Доставка(план or сам.план(), str(сам.цель), задача, сам.реестр,
                               каталог or сам.папка / "состояние")
        finally:
            os.chdir(прежний)


Фикстура.владелец = contextlib.contextmanager(Фикстура.владелец)



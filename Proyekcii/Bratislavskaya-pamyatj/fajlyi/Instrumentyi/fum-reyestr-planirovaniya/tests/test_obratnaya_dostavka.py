        сам.assertEqual(байты(план), байты(сам.ф.план()))
        сам.assertEqual(до, гит(сам.ф.источник, "show-ref"))
        сам.assertEqual(план["получатели"][0]["отношение"], "недоставленные коммиты")
        сам.assertTrue(план["получатели"][0]["сигнал_недоставки"])
        сам.assertFalse(план["источник"]["полная_приёмка"])


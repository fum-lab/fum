"""Вложенные Git-вызовы открытой фикстуры без аргументов и вывода."""
from pathlib import Path
import time


class НаблюдательПроцессов:
    def __init__(сам, запустить):
        сам.запустить = запустить
        сам.стадия = "без стадии"
        сам.повтор = 0
        сам.записи = []

    def __call__(сам, *аргументы, **параметры):
        команда = аргументы[0] if аргументы else параметры.get("args")
        подкоманда = None
        if isinstance(команда, (list, tuple)) and команда and Path(команда[0]).name in {"git", "git.exe"}:
            номер = 1
            while номер < len(команда) and команда[номер] == "-c":
                номер += 2
            подкоманда = команда[номер] if номер < len(команда) else "без подкоманды"
        начало = time.monotonic_ns()
        исход, код = "исключение", None
        try:
            результат = сам.запустить(*аргументы, **параметры)
            код = результат.returncode
            исход = "успешно" if код == 0 else "отказ"
            return результат
        except BaseException as ошибка:
            код = getattr(ошибка, "returncode", None)
            raise
        finally:
            if подкоманда is not None:
                сам.записи.append({
                    "стадия": сам.стадия, "повтор": сам.повтор, "команда": подкоманда,
                    "длительность_наносекунды": time.monotonic_ns() - начало,
                    "исход": исход, "код": код,
                })

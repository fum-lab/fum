"""Три локальные подготовки шести назначений с измеряемыми границами."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import statistics
import time
from unittest import mock

from test_отложенных_назначений import пакет_фикстуры, ЗАДАЧА
import отложенные_назначения as назначения


def измерить(выход):
    события = []
    итоги = []
    for повтор in range(3):
        with пакет_фикстуры() as (корень, пакет):
            исполнитель = назначения.ИсполнительНазначений(корень, ЗАДАЧА)
            глубина = 0
            фаза = "предпросмотр"

            def замерить(имя, операция, *аргументы, **параметры):
                nonlocal глубина
                начало = time.perf_counter_ns()
                уровень = глубина
                глубина += 1
                исход = "ошибка"
                try:
                    результат = операция(*аргументы, **параметры)
                    исход = "успех"
                    return результат
                finally:
                    глубина -= 1
                    события.append({"повтор": повтор + 1, "фаза": фаза, "стадия": имя, "глубина": уровень, "наносекунды": time.perf_counter_ns() - начало, "исход": исход})

            решение = назначения.вход.проверить_решение
            манифест = назначения.манифест_коммита
            установка = исполнитель.хранилище.применить_файлы
            with mock.patch.object(назначения.вход, "проверить_решение", side_effect=lambda *а, **к: замерить("первичный источник", решение, *а, **к)), \
                 mock.patch.object(назначения, "манифест_коммита", side_effect=lambda *а, **к: замерить("манифест исторического коммита", манифест, *а, **к)), \
                 mock.patch.object(исполнитель.хранилище, "применить_файлы", side_effect=lambda *а, **к: замерить("долговечная установка файлов", установка, *а, **к)):
                план = замерить("предпросмотр целиком", исполнитель.предпросмотр, пакет)
                assert len(set(план["назначения"].values())) == 6
                assert not исполнитель.хранилище.каталог.exists()
                фаза = "первая подготовка"
                первый = замерить("подготовка целиком", исполнитель.подготовить, пакет, план["sha256"])
                фаза = "точный повтор"
                второй = замерить("повтор целиком", исполнитель.подготовить, пакет, план["sha256"])
                assert первый == второй
                assert all((корень / имя).read_bytes() == данные.encode() for имя, данные in план["файлы"].items())
                состояние = исполнитель.хранилище.прочитать()
                assert состояние["приёмы"][план["пакет"]]["готов"] and not состояние["попытки"]
                итоги.append({"назначений": 6, "материалов": len(план["файлы"]), "байты_материалов": sum(len(данные.encode()) for данные in план["файлы"].values()), "равный_повтор": True})
    стадии = {имя: {"число": len(замеры), "медиана_мс": statistics.median(замеры) / 1e6} for имя in sorted({с["стадия"] for с in события}) for замеры in [[с["наносекунды"] for с in события if с["стадия"] == имя]]}
    каталог = Path(__file__).resolve().parents[1]
    файлы = sorted((каталог / "scripts").glob("*.py")) + [Path(__file__), Path(__file__).with_name("test_отложенных_назначений.py"), Path(__file__).with_name("test_входа_направления.py")]
    результат = {"схема": "fum.профиль-отложенных-назначений.1", "версия_питона": platform.python_version(), "система": platform.system(), "код": {ф.relative_to(каталог).as_posix(): hashlib.sha256(ф.read_bytes()).hexdigest() for ф in файлы}, "повторы": итоги, "события": события, "стадии": стадии,
                 "граница": "Три отдельные открытые Git-фикстуры по шесть карточек; создание фикстуры вне интервала. Реальные Git, проверка первичного JSONL, владение, замки и fsync. Метки оборачивают исходные функции без замены результата. Вложенные интервалы не суммируются с целыми. Профиль охватывает предпросмотр, подготовку и точный повтор; привязка, официальный MCP и наблюдение внешней задачи не измерены. Это небольшой синтетический вход, не профиль большого рабочего JSONL."}
    Path(выход).parent.mkdir(parents=True, exist_ok=True)
    Path(выход).write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(стадии, ensure_ascii=False))


if __name__ == "__main__":
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--выход", required=True)
    параметры = парсер.parse_args()
    измерить(параметры.выход)

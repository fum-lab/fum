"""Три независимых восстановления с настоящим реестром и локальным Git."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import statistics
import time
from unittest import mock

from test_исправления_приёма import неготовый_приём, приём_без_статуса, исполнение


def измерить(выход, сценарий="обратное отношение"):
    стадии = {имя: [] for имя in ("исправление целиком", "точный повтор", "сборка реестра внутри исправления", "установка стадий внутри исправления", "проверка границ карточек внутри исправления")}
    построить = исполнение.проверить_планирование
    границы = исполнение.проверить_границы_карточки
    for _ in range(3):
        контекст = приём_без_статуса() if сценарий == "пропущенный статус" else неготовый_приём()
        with контекст as набор:
            исполнитель, исправление = (набор[1], набор[3]) if сценарий == "пропущенный статус" else (набор[5], набор[7])
            def замерить(имя, операция, *аргументы, **параметры):
                начало = time.perf_counter_ns()
                try:
                    return операция(*аргументы, **параметры)
                finally:
                    стадии[имя].append(time.perf_counter_ns() - начало)
            def реестр(*аргументы):
                return замерить("сборка реестра внутри исправления", построить, *аргументы)
            применить = исполнитель.хранилище.применить_файлы
            def установка(*аргументы, **параметры):
                return замерить("установка стадий внутри исправления", применить, *аргументы, **параметры)
            def проверка_границ(*аргументы):
                return замерить("проверка границ карточек внутри исправления", границы, *аргументы)
            with mock.patch.object(исполнение, "проверить_планирование", side_effect=реестр), mock.patch.object(исполнитель.хранилище, "применить_файлы", side_effect=установка), mock.patch.object(исполнение, "проверить_границы_карточки", side_effect=проверка_границ):
                первый = замерить("исправление целиком", исполнитель.исправить_план, исправление)
                второй = замерить("точный повтор", исполнитель.исправить_план, исправление)
            assert первый == второй and первый["готов"]
    файлы = [Path(исполнение.__file__), Path(исполнение.хранилище.__file__), Path(__file__), Path(__file__).with_name("test_исправления_приёма.py")]
    результат = {"схема": "fum.профиль-исправления-приёма.1", "сценарий": сценарий, "версия_питона": platform.python_version(), "система": platform.system(),
                 "код": {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in файлы},
                 "стадии": {имя: {"наносекунды": замеры, "медиана_мс": statistics.median(замеры) / 1e6} for имя, замеры in стадии.items()},
                 "граница": "Три разные открытые Git-фикстуры. Построение фикстуры исключено. Настоящая проверка полного реестра, реальные fsync и Git; подстановки только измеряют вложенные операции. Вложенные интервалы не суммируются с целым исправлением. Сеть и native не используются."}
    Path(выход).parent.mkdir(parents=True, exist_ok=True)
    Path(выход).write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({имя: значение["медиана_мс"] for имя, значение in результат["стадии"].items()}, ensure_ascii=False))


if __name__ == "__main__":
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--выход", required=True)
    парсер.add_argument("--сценарий", choices=("обратное отношение", "пропущенный статус"), default="обратное отношение")
    параметры = парсер.parse_args()
    измерить(параметры.выход, параметры.сценарий)

"""Штатная навигация следующего этапа не теряет происхождение принятой пары."""
import copy
import json
from pathlib import Path
import subprocess
import sys
import unittest
from unittest import mock

from test_входа_направления import открытый_вход, ЗАДАЧА

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import исполнитель_приёма as исполнение


def подготовить_сдвиг(корень, источник, решение, *, закрыть=False):
    структура = исполнение.вход.структура
    первый = "2026-09-16_01-00-00_MSK_принять-направление"
    второй = "2026-09-16_02-00-00_MSK_оформить-результат"
    (корень / "Журнал").mkdir()
    (корень / "Журнал/README.md").write_text("# Журнал\n\n## Сессии\n\n")
    структура.start_session(корень, первый, "принять-направление",
        "Принять направление", ЗАДАЧА, ["Ранее.\n"])
    запрос = "Журнал/" + первый + "/запрос.md"
    решение["действие"] = "обновить"
    решение["задача"] = None
    исполнитель = исполнение.ИсполнительПриёма(корень, ЗАДАЧА)
    with mock.patch.object(исполнение, "проверить_планирование", return_value="{}\n"):
        результат = исполнитель.подготовить(источник, ЗАДАЧА, решение, запрос, [])
    with исполнитель.хранилище.изменить() as состояние:
        прежде = copy.deepcopy(исполнитель._прочитать(состояние, результат["событие"]))
    if закрыть:
        отчёты = исполнение.вход.отчёты
        отчёты.выполнить_запуск(корень, Path(запрос), "Адресное наблюдение", "корень",
            None, 10, [sys.executable, "-c", "pass"], класс_проверки="адресная")
        отчёты.выполнить_закрытие(корень, Path(запрос))
    структура.start_session(корень, второй, "оформить-результат",
        "Оформить результат", ЗАДАЧА, ["Продолжить.\n"])
    return исполнитель, результат, запрос, прежде


class ПроверкаУстойчивойПары(unittest.TestCase):
    def test_закрытый_журнал_сверяется_без_возобновления(проверка):
        with открытый_вход() as (корень, источник, решение):
            исполнитель, результат, запрос, прежде = подготовить_сдвиг(корень, источник, решение, закрыть=True)
            снимок = Path(корень / запрос).parent / "материалы/запуски-проверок/снимок.json"
            байты_снимка = снимок.read_bytes()
            отчёт = Path(корень / запрос).with_name("отчёт.md").read_bytes()
            исполнитель.сохранить_устойчивую_пару(результат["событие"])
            исполнитель._сверить_местное(прежде, {"команда": "Направление — математика.\n"})
            проверка.assertEqual(снимок.read_bytes(), байты_снимка)
            проверка.assertEqual(Path(корень / запрос).with_name("отчёт.md").read_bytes(), отчёт)
            исполнение.хранилище.гит(корень, "add", ".")
            исполнение.хранилище.гит(корень, "commit", "-qm", "Закрытая пара")
            коммит = исполнение.хранилище.гит(корень, "rev-parse", "HEAD").strip()
            ветка = исполнение.хранилище.гит(корень, "symbolic-ref", "HEAD").strip()
            with mock.patch.object(исполнение, "проверить_инструменты"):
                постановка = исполнитель.закрепить_постановку(результат["событие"], коммит, ветка)
            проверка.assertEqual(постановка["коммит"], коммит)

    def test_изменённое_происхождение_не_создаёт_соответствия(проверка):
        for вид in ("команда", "владелец", "повтор", "скрытие", "префикс", "ответ", "основание", "маркер", "раздел"):
            with проверка.subTest(вид=вид), открытый_вход() as (корень, источник, решение):
                исполнитель, результат, запрос, прежде = подготовить_сдвиг(корень, источник, решение)
                путь = корень / запрос
                текст = путь.read_text()
                маркер = "<!-- FUM-INTAKE: " + прежде["экземпляр"] + " -->"
                if вид == "команда":
                    текст = текст.replace("Направление — математика.", "Направление — физика.")
                elif вид == "владелец":
                    текст = текст.replace(ЗАДАЧА, "00000000-0000-0000-0000-000000000999")
                elif вид == "повтор":
                    текст += "\n" + маркер + "\n"
                elif вид == "скрытие":
                    текст = текст.replace(маркер, "`````text\n" + маркер)
                elif вид == "префикс":
                    текст = текст.replace("## Текст запроса", "Дополнительное пояснение.\n\n## Текст запроса")
                elif вид == "маркер":
                    текст = текст.replace(маркер, "<!-- FUM-INTAKE: " + "0" * 64 + " -->")
                elif вид == "раздел":
                    начало = текст.index(маркер)
                    конец = текст.index("## Идентификатор сеанса Codex")
                    блок = текст[начало:конец]
                    текст = текст[:начало] + текст[конец:] + "\n## Иной раздел\n\n" + блок
                else:
                    путь = путь.with_name("отчёт.md")
                    ключ = "ответ" if вид == "ответ" else "основание"
                    текст = путь.read_text().replace(решение[ключ], "Другой ответ.")
                путь.write_text(текст)
                with проверка.assertRaises(ValueError):
                    исполнитель.сохранить_устойчивую_пару(результат["событие"])
                проверка.assertFalse((Path(корень / запрос).parent / "материалы/устойчивая-пара").exists())
                with исполнитель.хранилище.изменить() as состояние:
                    проверка.assertEqual(исполнитель._прочитать(состояние, результат["событие"]), прежде)

    def test_повреждённый_исходный_диапазон_не_восстанавливается_по_тексту(проверка):
        with открытый_вход() as (корень, источник, решение):
            исполнитель, результат, запрос, прежде = подготовить_сдвиг(корень, источник, решение)
            for имя in ("команда", "ответ", "основание"):
                with проверка.subTest(имя=имя):
                    повреждённое = copy.deepcopy(прежде)
                    повреждённое["свидетельства"][имя]["начало"] += 1
                    with проверка.assertRaises(ValueError):
                        исполнение.устойчивая_пара.построить(повреждённое, [],
                            lambda имя: (корень / имя).read_bytes(), исполнение.сверить_журнал_коммита)

    def test_команда_интерфейса_сохраняет_то_же_соответствие(проверка):
        with открытый_вход() as (корень, источник, решение):
            исполнитель, результат, запрос, прежде = подготовить_сдвиг(корень, источник, решение)
            процесс = subprocess.run([sys.executable, "-B", str(Path(исполнение.__file__).with_name("принять-направление.py")),
                "--корень-репозитория", str(корень), "--задача", ЗАДАЧА,
                "сохранить-устойчивую-пару", "--событие", результат["событие"]],
                cwd=корень, capture_output=True, text=True, timeout=30)
            проверка.assertEqual(процесс.returncode, 0, процесс.stderr)
            проверка.assertEqual(json.loads(процесс.stdout), исполнитель.сохранить_устойчивую_пару(результат["событие"]))

    def test_прерывание_установки_сохраняет_исходный_приём(проверка):
        with открытый_вход() as (корень, источник, решение):
            исполнитель, результат, запрос, прежде = подготовить_сдвиг(корень, источник, решение)
            устойчивая = исполнение.устойчивая_пара.устойчивые
            установить = устойчивая.установить
            вызовов = 0
            def прервать(корень, файл):
                nonlocal вызовов
                вызовов += 1
                if вызовов == 2:
                    raise OSError("Прерывание перед вторым материалом")
                return установить(корень, файл)
            with mock.patch.object(устойчивая, "установить", side_effect=прервать), проверка.assertRaises(OSError):
                исполнитель.сохранить_устойчивую_пару(результат["событие"])
            соответствие = исполнитель.сохранить_устойчивую_пару(результат["событие"])
            проверка.assertEqual(len(соответствие["файлы"]), 2)
            with исполнитель.хранилище.изменить() as состояние:
                проверка.assertEqual(исполнитель._прочитать(состояние, результат["событие"]), прежде)

    def test_коммит_без_точных_устойчивых_материалов_отклоняется(проверка):
        for вид in ("нет", "квитанция", "команда"):
            with проверка.subTest(вид=вид), открытый_вход() as (корень, источник, решение):
                исполнитель, результат, запрос, прежде = подготовить_сдвиг(корень, источник, решение)
                if вид != "нет":
                    соответствие = исполнитель.сохранить_устойчивую_пару(результат["событие"])
                    окончание = "соответствие.json" if вид == "квитанция" else "команда.txt"
                    имя = next(имя for имя in соответствие["файлы"] if имя.endswith(окончание))
                    with (корень / имя).open("ab") as поток:
                        поток.write(b" ")
                исполнение.хранилище.гит(корень, "add", ".")
                исполнение.хранилище.гит(корень, "commit", "-qm", "Неполное соответствие")
                коммит = исполнение.хранилище.гит(корень, "rev-parse", "HEAD").strip()
                ветка = исполнение.хранилище.гит(корень, "symbolic-ref", "HEAD").strip()
                with mock.patch.object(исполнение, "проверить_инструменты"), проверка.assertRaises(ValueError):
                    исполнитель.закрепить_постановку(результат["событие"], коммит, ветка)
                with исполнитель.хранилище.изменить() as состояние:
                    проверка.assertEqual(исполнитель._прочитать(состояние, результат["событие"]), прежде)

    def test_следующий_журнал_не_теряет_принятую_пару(проверка):
        with открытый_вход() as (корень, источник, решение):
            исполнитель, результат, запрос, прежде = подготовить_сдвиг(корень, источник, решение)
            старый = результат["свидетельства"]["команда"]
            данные = (корень / запрос).read_bytes()
            проверка.assertNotEqual(данные[старый["начало"]:старый["конец"]],
                прежде["файлы"][запрос].encode()[старый["начало"]:старый["конец"]])
            соответствие = исполнитель.сохранить_устойчивую_пару(результат["событие"])
            проверка.assertEqual(соответствие,
                исполнитель.сохранить_устойчивую_пару(результат["событие"]))
            исполнение.хранилище.гит(корень, "add", ".")
            исполнение.хранилище.гит(корень, "commit", "-qm", "Следующий этап")
            коммит = исполнение.хранилище.гит(корень, "rev-parse", "HEAD").strip()
            ветка = исполнение.хранилище.гит(корень, "symbolic-ref", "HEAD").strip()
            with mock.patch.object(исполнение, "проверить_инструменты"):
                постановка = исполнитель.закрепить_постановку(результат["событие"], коммит, ветка)
            проверка.assertEqual(постановка["коммит"], коммит)
            with исполнитель.хранилище.изменить() as состояние:
                после = исполнитель._прочитать(состояние, результат["событие"])
                for имя in ("свидетельства", "файлы", "решение", "номера", "карточки"):
                    проверка.assertEqual(после[имя], прежде[имя])


if __name__ == "__main__":
    unittest.main()

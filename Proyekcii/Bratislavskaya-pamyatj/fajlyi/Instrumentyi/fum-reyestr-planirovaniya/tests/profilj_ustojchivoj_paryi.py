"""Открытый профиль сохранения соответствия и закрепления закрытой пары."""
import argparse
import hashlib
import json
from pathlib import Path
import time
from unittest import mock

from test_устойчивой_пары_приёма import подготовить_сдвиг, исполнение
from test_входа_направления import открытый_вход


def измерить():
    образцы = []
    for номер in range(3):
        начало = time.monotonic_ns()
        with открытый_вход() as (корень, источник, решение):
            исполнитель, результат, запрос, прежде = подготовить_сдвиг(корень, источник, решение, закрыть=True)
            подготовлено = time.monotonic_ns()
            первый = исполнитель.сохранить_устойчивую_пару(результат["событие"])
            сохранено = time.monotonic_ns()
            повтор = исполнитель.сохранить_устойчивую_пару(результат["событие"])
            повторено = time.monotonic_ns()
            assert первый == повтор
            исполнение.хранилище.гит(корень, "add", ".")
            исполнение.хранилище.гит(корень, "commit", "-qm", "Профиль устойчивой пары")
            коммит = исполнение.хранилище.гит(корень, "rev-parse", "HEAD").strip()
            ветка = исполнение.хранилище.гит(корень, "symbolic-ref", "HEAD").strip()
            зафиксировано = time.monotonic_ns()
            with mock.patch.object(исполнение, "проверить_инструменты"):
                постановка = исполнитель.закрепить_постановку(результат["событие"], коммит, ветка)
            закреплено = time.monotonic_ns()
            assert all(постановка["файлы"][имя] == хэш for имя, хэш in первый["файлы"].items())
            with исполнитель.хранилище.изменить() as состояние:
                после = исполнитель._прочитать(состояние, результат["событие"])
                assert all(после[имя] == прежде[имя] for имя in ("свидетельства", "файлы", "решение", "номера", "карточки"))
            конец = time.monotonic_ns()
            образцы.append({"номер": номер + 1, "байтов_источника": источник.stat().st_size,
                "байтов_материалов": sum((корень / имя).stat().st_size for имя in первый["файлы"]),
                "стадии_наносекунды": {"подготовка_фикстуры_и_сдвига": подготовлено - начало,
                    "сохранение": сохранено - подготовлено, "повтор": повторено - сохранено,
                    "коммит": зафиксировано - повторено, "закрепление": закреплено - зафиксировано,
                    "проверка_неизменности": конец - закреплено}, "всего_наносекунды": конец - начало})
    корень = Path(__file__).resolve().parents[3]
    пути = [Path(исполнение.__file__), Path(исполнение.устойчивая_пара.__file__),
        Path(исполнение.устойчивая_пара.устойчивые.__file__), Path(__file__),
        Path(__file__).with_name("test_устойчивой_пары_приёма.py")]
    return {"схема": "fum.профиль-устойчивой-пары.1", "образцы": образцы,
        "реализация": {str(путь.relative_to(корень)): hashlib.sha256(путь.read_bytes()).hexdigest() for путь in пути},
        "граница": "Три независимые открытые Git/JSONL-фикстуры. Включены подготовка, приём, закрытие v3, следующий start, сохранение и повтор соответствия, коммит, закрепление и сверка неизменности. Удаление временных файлов после измерения исключено.",
        "подстановки": "Глобальный сборщик реестра и проверка расположения исполняемого кода в временном checkout подменены. Читатель, файловые операции, навигация, закрытие отчёта, Git и проверка соответствия настоящие.",
        "ограничение": "Не измеряет живой большой JSONL, полную приёмку FUM, токены или человеческое время; ускорение не заявляется."}


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", required=True, type=Path)
    параметры = разбор.parse_args()
    результат = измерить()
    параметры.выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n")

ЗАДАЧА = "00000000-0000-0000-0000-000000000201"
РАЗДЕЛЫ = ("Наблюдаемый сбой", "Граница повторения", "Проявления", "Ожидание и классификация", "Механизм и системное устранение", "Связанные шаги", "Критерии закрытия", "Источники")


def сбой(номер=80, *, статус="активна", основной="FUM-STEP-0080"):
    добавочный = {"устранена": "Подтверждение устранения", "поглощена": "Поглощение", "снята": "Причина снятия"}.get(статус)
    разделы = РАЗДЕЛЫ + ((добавочный,) if добавочный else ())
    return {"операция": "создать", "номер": f"FUM-СБОЙ-{номер:04d}", "имя": f"открытый-пример-{номер}", "статус": статус, "заголовок": f"Открытый пример {номер}", "содержимое": "\n\n".join("## " + раздел + "\n\nОткрытое явное наблюдение." for раздел in разделы), "до_sha256": None, "проявлений": 1, "основной_шаг": основной}


def шаг(номер=80):
    return {"операция": "создать", "номер": f"FUM-STEP-{номер:04d}", "имя": f"исследовать-пример-{номер}", "статус": "active", "заголовок": f"Исследовать пример {номер}", "содержимое": "## Задача\n\nОткрытая проверка.\n\n## Почему сейчас\n\nЗамечен эффект.\n\n## Критерии завершения\n\n- Проверяемый исход.\n\n## Источники\n\n- [Открытое основание](../../README.md)\n", "до_sha256": None}


def пакет():
    return {"схема": "fum.пакет-диагностики.1", "сбои": [сбой()], "шаги": [шаг()]}


class ПакетДиагностики(unittest.TestCase):
    def setUp(проверка):
        временный = tempfile.TemporaryDirectory()
        проверка.addCleanup(временный.cleanup)
        проверка.корень = Path(временный.name).resolve()
        проверка.гит("init", "-q", "-b", "codex/открытая-фикстура")
        проверка.гит("config", "user.name", "Открытая фикстура")
        проверка.гит("config", "user.email", "fixture@example.invalid")
        (проверка.корень / "README.md").write_text("# Открытый источник\n")
        for каталог, столбцы in (("Сбои", ["Идентификатор", "Статус", "Карточка", "Проявлений", "Основной шаг устранения"]), ("Планирование/карточки-шагов", ["Идентификатор", "Статус", "Карточка"])):
            (проверка.корень / каталог).mkdir(parents=True)
            (проверка.корень / каталог / "README.md").write_text("# Индекс\n\n| " + " | ".join(столбцы) + " |\n| " + " | ".join("---" for _ in столбцы) + " |\n\nХвост сохраняется.\n")
        проверка.гит("add", ".")
        проверка.гит("commit", "-qm", "Основа")

    def гит(проверка, *аргументы):
        return subprocess.run(["git", *аргументы], cwd=проверка.корень, check=True, capture_output=True).stdout.decode().strip()

    def test_пять_сбоев_два_шага_и_явное_обновление(проверка):
        начальный = выпуск.подготовить(проверка.корень, ЗАДАЧА, пакет())
        выпуск.применить(проверка.корень, ЗАДАЧА, начальный)
        старый = проверка.корень / "Сбои/FUM-СБОЙ-0080-открытый-пример-80.md"
        обновление = сбой()
        обновление.update(операция="обновить", до_sha256=hashlib.sha256(старый.read_bytes()).hexdigest(), проявлений=2, основной_шаг="FUM-STEP-0082")
        обновление["содержимое"] += "\nИсторический [источник](https://example.invalid/commit/012345/path.md); FUM-СБОЙ-0020/ПРОЯВЛЕНИЕ-0001.\n"
        данные = {"схема": "fum.пакет-диагностики.1", "сбои": [обновление] + [сбой(номер, статус="устранена", основной=None) for номер in range(81, 86)], "шаги": [шаг(81), шаг(82)]}
        план = выпуск.подготовить(проверка.корень, ЗАДАЧА, данные)
        проверка.assertEqual(10, len(план["данные"]["файлы"]))
        выпуск.применить(проверка.корень, ЗАДАЧА, план)
        индекс = (проверка.корень / "Планирование/карточки-шагов/README.md").read_text()
        проверка.assertIn("FUM-STEP-0081", индекс)
        проверка.assertIn("FUM-STEP-0082", индекс)
        проверка.assertIn("Хвост сохраняется.", индекс)
        проверка.assertIn("https://example.invalid/commit/012345/path.md", старый.read_text())
        проверка.assertIn("—", (проверка.корень / "Сбои/README.md").read_text())

    def test_план_не_меняет_дерево_и_повтор_идемпотентен(проверка):
        до = проверка.гит("status", "--porcelain=v1", "--untracked-files=all")
        план = выпуск.подготовить(проверка.корень, ЗАДАЧА, пакет())
        проверка.assertEqual(до, проверка.гит("status", "--porcelain=v1", "--untracked-files=all"))
        первый = выпуск.применить(проверка.корень, ЗАДАЧА, план)
        проверка.assertEqual(первый, выпуск.применить(проверка.корень, ЗАДАЧА, план))

    def test_изменённый_индекс_закрывает_весь_пакет(проверка):
        план = выпуск.подготовить(проверка.корень, ЗАДАЧА, пакет())
        индекс = проверка.корень / "Сбои/README.md"
        индекс.write_text(индекс.read_text() + "Чужая правка\n")

    def test_команда_плана_и_применения(проверка):
        with tempfile.TemporaryDirectory() as имя:
            вход = Path(имя).resolve() / "вход.json"
            вход.write_bytes(хранение.байты(пакет()))
            команда = [sys.executable, "-B", str(Path(выпуск.__file__)), "план", "--корень", str(проверка.корень), "--задача", ЗАДАЧА, "--вход", str(вход)]
            план = subprocess.run(команда, check=True, capture_output=True).stdout
            проверка.assertEqual("fum.план-пакета-диагностики.1", json.loads(план)["данные"]["схема"])
            вход.write_bytes(план)
            команда[3] = "применить"
            квитанция = subprocess.run(команда, check=True, capture_output=True).stdout
            проверка.assertEqual(4, len(json.loads(квитанция)))
            проверка.assertEqual(квитанция, subprocess.run(команда, check=True, capture_output=True).stdout)

    def test_исторические_байты_публикуемой_карточки_нормализуются(проверка):
        имя = "Сбои/FUM-СБОЙ-0035-пропуск-удалённого-пути-проекции-в-запросе.md"
        база = "8609003af7fdb6ef5dddf21c51cd6607ddb34088"
        источник = Path(__file__).resolve().parents[3]
        прежние = subprocess.run(["git", "show", база + ":" + имя], cwd=источник, check=True, capture_output=True).stdout
        путь = проверка.корень / имя
        путь.write_bytes(прежние)
        индекс = проверка.корень / "Сбои/README.md"
        индекс.write_text(выпуск.изменить_индекс(индекс.read_text(), выпуск.ЗАГОЛОВКИ_СБОЕВ, ["FUM-СБОЙ-0035", "`устранена`", "[Прежняя карточка](" + путь.name + ")", "1", "—"], False))
        запись = сбой(35)
        запись.update(операция="обновить", имя="пропуск-удалённого-пути-проекции-в-запросе", до_sha256=hashlib.sha256(прежние).hexdigest())
        данные = {"схема": "fum.пакет-диагностики.1", "сбои": [запись], "шаги": [шаг()]}
        план = выпуск.подготовить(проверка.корень, ЗАДАЧА, данные)
        проверка.assertEqual(прежние.decode("utf-8"), план["данные"]["файлы"][имя]["до"])
        выпуск.применить(проверка.корень, ЗАДАЧА, план)
        проверка.assertEqual("FUM-СБОЙ-0035", выпуск.разобрать_сбой(путь.read_text())["идентификатор_сбоя"])
        for испорчено in (прежние.replace(b"# FUM-", b"# WRONG-FUM-", 1), прежние.replace("- Идентификатор: `FUM-СБОЙ-0035`.".encode(), "- Идентификатор: `FUM-СБОЙ-0036`.".encode()), прежние.replace("- Идентификатор:".encode(), "- Идентификатор: `FUM-СБОЙ-0035`.\n- Идентификатор:".encode())):
            путь.write_bytes(испорчено)
            запись["до_sha256"] = hashlib.sha256(испорчено).hexdigest()
            with проверка.subTest(хэш=запись["до_sha256"]), проверка.assertRaises(хранение.ОшибкаПриёма):
                выпуск.подготовить(проверка.корень, ЗАДАЧА, данные)

    def test_два_плана_одного_номера_после_частичной_записи(проверка):
        второй = {"схема": "fum.пакет-диагностики.1", "сбои": [сбой()], "шаги": []}
        первый = copy.deepcopy(второй)
        первый["сбои"][0]["имя"] = "иное-имя"
        план_первого = выпуск.подготовить(проверка.корень, ЗАДАЧА, первый)
        план_второго = выпуск.подготовить(проверка.корень, ЗАДАЧА, второй)
        исходная = хранение.установить
        def прервать(путь, данные):
            if путь == проверка.корень / "Сбои/README.md":
                raise OSError("Остановлено после карточки до индекса")
            исходная(путь, данные)
        with mock.patch.object(хранение, "установить", side_effect=прервать), проверка.assertRaises(OSError):
            выпуск.применить(проверка.корень, ЗАДАЧА, план_второго)
        проверка.assertTrue((проверка.корень / "Сбои/FUM-СБОЙ-0080-открытый-пример-80.md").exists())
        with проверка.assertRaises(хранение.ОшибкаПриёма):
            выпуск.применить(проверка.корень, ЗАДАЧА, план_первого)
        проверка.assertFalse((проверка.корень / "Сбои/FUM-СБОЙ-0080-иное-имя.md").exists())
        выпуск.применить(проверка.корень, ЗАДАЧА, план_второго)


    def test_частичное_применение_продолжается(проверка):
        план = выпуск.подготовить(проверка.корень, ЗАДАЧА, пакет())
        исходная = хранение.установить
        def прервать(путь, данные):
            if путь == проверка.корень / "Сбои/README.md":
                raise OSError("Открытое прерывание")
            исходная(путь, данные)
        with mock.patch.object(хранение, "установить", side_effect=прервать):
            with проверка.assertRaises(OSError):
                выпуск.применить(проверка.корень, ЗАДАЧА, план)
        выпуск.применить(проверка.корень, ЗАДАЧА, план)
        проверка.assertIn("FUM-СБОЙ-0080", (проверка.корень / "Сбои/README.md").read_text())

    def test_закрытые_поля_путь_дубликат_и_неверный_шаг(проверка):
        for вид in ("путь", "дубликат", "поле", "тело", "активный_null", "хэш"):
            данные = пакет()
            if вид == "путь": данные["сбои"][0]["имя"] = "../чужое"
            if вид == "дубликат": данные["сбои"].append(copy.deepcopy(данные["сбои"][0]))
            if вид == "поле": данные["сбои"][0]["лишнее"] = True
            if вид == "тело": данные["шаги"][0]["содержимое"] = "неполный STEP"
            if вид == "активный_null": данные["сбои"][0]["основной_шаг"] = None
            if вид == "хэш": данные["сбои"][0]["до_sha256"] = "0" * 64
            with проверка.subTest(вид=вид), проверка.assertRaises(хранение.ОшибкаПриёма):
                выпуск.подготовить(проверка.корень, ЗАДАЧА, данные)


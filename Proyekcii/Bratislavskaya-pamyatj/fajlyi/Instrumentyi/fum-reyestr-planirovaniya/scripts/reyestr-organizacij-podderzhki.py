#!/usr/bin/env python3
"""Импорт, проверка, выпуск и добавление датированного наблюдения поддержки FUM."""
import argparse
from pathlib import Path
import re
import sys

import реестр_поддержки as реестр
from project_files import ProjectFilesError
sys.path.insert(0, str(реестр.КОРЕНЬ / "Инструменты/fum-materialyi-zaprosov/scripts"))
from source_archive import write_text_atomically


def выполнить(параметры):
    корень = параметры.корень_репозитория.resolve()
    def путь(имя, существует=True):
        return корень / реестр.normalized_project_relative_path(имя, корень, must_exist=существует)
    исходник = реестр.разобрать(путь(параметры.исследования).read_bytes())
    вход = путь(параметры.вход, параметры.операция != "импортировать")
    if параметры.операция == "импортировать":
        новое = реестр.байты(реестр.импортировать(исходник)).decode()
        реестр.требовать(not вход.exists() or вход.read_text() == новое, "Импорт не перезаписывает заполненный вход")
        вход.parent.mkdir(parents=True, exist_ok=True)
        write_text_atomically(вход, новое)
        return {"исход": "импортировано", "следующий_шаг": "Заполнить предметные варианты и источники; заготовка ещё не реестр"}
    исходные_байты = вход.read_bytes()
    данные = реестр.разобрать(исходные_байты)
    if параметры.операция == "обновить":
        реестр.требовать(все_параметры(параметры, ["организация", "вариант", "наблюдение", "ожидаемый_хэш"]), "Для обновления нужны организация, вариант, наблюдение и ожидаемый хэш")
        наблюдение = реестр.разобрать(путь(параметры.наблюдение).read_bytes())
        новое = реестр.добавить_проверку(данные, исходник, параметры.организация, параметры.вариант, наблюдение, параметры.ожидаемый_хэш)
        реестр.собрать(новое, исходник, наблюдение["дата"], корень)
        план = {"исход": "план", "до": реестр.хэш(данные), "после": реестр.хэш(новое), "путь": параметры.вход}
        if параметры.применить:
            реестр.требовать(вход.read_bytes() == исходные_байты, "Вход изменился во время подготовки")
            write_text_atomically(вход, реестр.байты(новое).decode())
            план["исход"] = "применено"
        return план
    реестр.требовать(параметры.дата and параметры.выход, "Для выпуска или проверки нужны --дата и --выход")
    результаты = реестр.сформировать(данные, исходник, параметры.дата, корень)
    пути = {имя: путь(параметры.выход + "/" + имя, параметры.операция == "проверить") for имя in результаты}
    защищённые = {вход, путь(параметры.исследования)}
    for организация in данные["организации"]:
        for вариант in организация["варианты"]:
            for проверка in вариант["проверки"]:
                for источник in проверка["источники"]:
                    if источник["снимок"]:
                        защищённые.add(путь(источник["снимок"]["путь"]))
    реестр.требовать(not set(пути.values()) & защищённые, "Выход пересекается с входом, исследованиями или снимком")
    if параметры.операция == "проверить":
        for имя, ожидаемое in результаты.items():
            фактическое = пути[имя].read_text()
            if имя.endswith(".md"):
                фактическое = re.sub(r"\n*<!-- FUM-MD-RECENCY:BEGIN -->\n[\s\S]*?<!-- FUM-MD-RECENCY:END -->\n?\Z", "\n", фактическое)
                ожидаемое = ожидаемое.rstrip() + "\n"
            реестр.требовать(фактическое == ожидаемое, "Устаревший выпуск: " + имя)
    else:
        for имя, содержимое in результаты.items():
            пути[имя].parent.mkdir(parents=True, exist_ok=True)
            write_text_atomically(пути[имя], содержимое)
    return {"исход": "проверено" if параметры.операция == "проверить" else "сформировано", "дата": параметры.дата, "число_организаций": len(данные["организации"]), "вход_sha256": реестр.хэш(данные)}


def все_параметры(параметры, имена):
    return all(getattr(параметры, имя) for имя in имена)


def главный():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("операция", choices=["импортировать", "сформировать", "проверить", "обновить"])
    парсер.add_argument("--корень-репозитория", type=Path, default=Path.cwd())
    парсер.add_argument("--исследования", required=True)
    парсер.add_argument("--вход", required=True)
    for имя in ("дата", "выход", "организация", "вариант", "наблюдение", "ожидаемый-хэш"):
        парсер.add_argument("--" + имя)
    парсер.add_argument("--применить", action="store_true")
    параметры = парсер.parse_args()
    try:
        print(реестр.байты(выполнить(параметры)).decode(), end="")
        return 0
    except (ValueError, OSError, KeyError, TypeError, ProjectFilesError) as ошибка:
        print("Реестр не выпущен: " + str(ошибка), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(главный())

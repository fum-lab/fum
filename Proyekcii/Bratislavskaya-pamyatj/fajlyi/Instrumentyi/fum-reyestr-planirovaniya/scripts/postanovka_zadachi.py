"""Постановка из точного Git-коммита и раннее наблюдение новой задачи."""
import fcntl
import hashlib
import os
from pathlib import Path

import приём_направления as хранение
from приём_направления import ОшибкаПриёма, требовать, гит


def проверить_постановку(корень, постановка):
    хранение.поля(постановка, {"коммит", "ветка", "файлы"})
    коммит, ветка, файлы = постановка["коммит"], постановка["ветка"], постановка["файлы"]
    требовать(хранение.шестнадцатеричный(коммит, 40), "Нужен полный коммит постановки")
    требовать(хранение.ветка_писателя(ветка), "Нужен полный принадлежащий задаче ref постановки")
    требовать(гит(корень, "cat-file", "-t", коммит).strip() == "commit", "Постановка не является коммитом")
    требовать(гит(корень, "show-ref", "--hash", "--verify", ветка).strip() == коммит, "Ветка сдвинулась от коммита постановки")
    требовать(type(файлы) is dict and файлы, "Нет доступных файлов постановки; одного prompt недостаточно")
    for имя, ожидаемый in файлы.items():
        требовать(type(имя) is str and имя and not Path(имя).is_absolute() and ".." not in Path(имя).parts and Path(имя).as_posix() == имя, "Неверный путь постановки")
        требовать(хранение.шестнадцатеричный(ожидаемый), "Нужен точный хэш файла постановки")
        записи = гит(корень, "ls-tree", "-z", коммит, "--", ":(literal)" + имя).split("\0")
        требовать(len(записи) == 2 and записи[-1] == "" and "\t" in записи[0], "Файл постановки отсутствует")
        свойства, путь = записи[0].split("\t", 1)
        части = свойства.split(" ")
        требовать(путь == имя and len(части) == 3 and части[0] in {"100644", "100755"} and части[1] == "blob", "Постановке нужен обычный файл")
        данные = гит(корень, "cat-file", "blob", части[2], сырые=True)
        требовать(hashlib.sha256(данные).hexdigest() == ожидаемый, "Подменён файл постановки")
    требовать(гит(корень, "show-ref", "--hash", "--verify", ветка).strip() == коммит, "Ветка сдвинулась при проверке постановки")
    return {**постановка, "startingState": {"type": "branch", "branchName": ветка}}


def прочитать_ограниченный_префикс(источник, завершено):
    путь = Path(источник).absolute()
    хранение.безопасный_путь(путь)
    записи = []
    префикс = bytearray()
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
        состояние = os.fstat(поток.fileno())
        while True:
            строка = поток.readline(16 * 1024 * 1024 - len(префикс) + 1)
            if not строка:
                break
            требовать(len(префикс) + len(строка) <= 16 * 1024 * 1024 and строка.endswith(b"\n"), "Нет ограниченного завершённого начала JSONL")
            префикс.extend(строка)
            запись = хранение.разобрать(строка)
            требовать(type(запись) is dict, "Неизвестная начальная запись JSONL")
            записи.append(запись)
            if завершено(запись):
                break
        после = путь.stat()
        требовать((после.st_dev, после.st_ino) == (состояние.st_dev, состояние.st_ino) and после.st_size >= len(префикс), "Источник подменён либо усечён")
        поток.seek(0)
        требовать(поток.read(len(префикс)) == префикс, "Начальный префикс источника изменился")
    return записи, {"граница": len(префикс), "sha256": hashlib.sha256(префикс).hexdigest()}


def прочитать_начало_источника(источник):
    записи, граница = прочитать_ограниченный_префикс(источник, lambda запись: запись.get("type") == "turn_context")
    начала = [запись.get("payload") for запись in записи if запись.get("type") == "session_meta"]
    контексты = [запись.get("payload") for запись in записи if запись.get("type") == "turn_context"]
    требовать(len(начала) == len(контексты) == 1 and type(начала[0]) is dict and type(контексты[0]) is dict, "Не наблюдены единственные нативное начало и первая модель")
    return начала[0], контексты[0], граница


def проверить_нативное_поручение(источник, отправитель, поручение):
    """Точный наблюдённый транспорт create_thread, без приписывания человеку."""
    def завершено(запись):
        данные = запись.get("payload", {})
        return запись.get("type") == "response_item" and type(данные) is dict and (
            данные.get("type") == "function_call_output" and данные.get("name") == "create_thread"
            or данные.get("type") == "message" and данные.get("role") == "assistant")
    записи, граница = прочитать_ограниченный_префикс(источник, завершено)
    ожидаемое = "<codex_delegation>\n  <source_thread_id>" + отправитель + "</source_thread_id>\n  <input>" + поручение + "</input>\n</codex_delegation>"
    совпадения = [запись for запись in записи if запись.get("type") == "response_item" and type(запись.get("payload")) is dict
                  and запись["payload"].get("type") == "function_call_output" and запись["payload"].get("name") == "create_thread"
                  and запись["payload"].get("output") == ожидаемое]
    требовать(len(совпадения) == 1, "Не подтверждено точное первоначальное нативное поручение своего корня")
    return граница


def наблюдать(корень, задача, коммит, источник):
    требовать(хранение.шестнадцатеричный(коммит, 40), "Нужен ожидаемый начальный коммит")
    владение = хранение.Хранилище(корень, задача)._наблюдать_владельца()
    начало, контекст, граница = прочитать_начало_источника(источник)
    требовать(начало.get("id") == задача and начало.get("cwd") == владение["путь"] and контекст.get("cwd") == владение["путь"], "Источник относится к другой задаче или дереву")
    требовать(type(начало.get("git")) is dict and начало["git"].get("commit_hash") == коммит, "Нативный начальный HEAD отличается от постановки")
    требовать(контекст.get("model") == "gpt-6-astra" and контекст.get("effort") == "ultra", "Фактическая первая модель не соответствует запросу")
    return владение, {"схема": "fum.начальная-база-задачи.1", "задача": задача, "корень": владение["путь"], "ref": владение["ref"], "начальный_HEAD": коммит, "модель": контекст["model"], "рассуждение": контекст["effort"], "источник": граница}


def путь_подтверждения(корень):
    каталог = Path(гит(корень, "rev-parse", "--absolute-git-dir").strip())
    хранение.безопасный_путь(каталог, каталог=True)
    return каталог / "fum-начальная-база-задачи.json"


def прочитать_подтверждение(корень, задача, коммит, источник):
    путь = путь_подтверждения(корень)
    хранение.безопасный_путь(путь)
    требовать(путь.is_file(), "Нет сохранённого раннего подтверждения")
    конверт = хранение.разобрать(путь.read_bytes())
    хранение.поля(конверт, {"данные", "sha256"})
    запись = конверт["данные"]
    требовать(конверт["sha256"] == хранение.хэш(запись), "Повреждено раннее подтверждение")
    владение, ожидаемое = наблюдать(корень, задача, коммит, источник)
    требовать(хранение.байты(запись) == хранение.байты(ожидаемое), "Раннее подтверждение не соответствует первичному источнику")
    гит(корень, "merge-base", "--is-ancestor", коммит, владение["HEAD"])
    return запись


def подтвердить_начало(корень, задача, коммит, источник):
    """Вызывается новой задачей до первой записи checkout; повтор только читает."""
    путь = путь_подтверждения(корень)
    замок = путь.with_name("fum-начальная-база-задачи.lock")
    хранение.безопасный_путь(замок)
    with os.fdopen(os.open(замок, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600), "r+b") as поток:
        fcntl.flock(поток, fcntl.LOCK_EX)
        if путь.exists():
            return прочитать_подтверждение(корень, задача, коммит, источник)
        владение, запись = наблюдать(корень, задача, коммит, источник)
        требовать(владение["HEAD"] == коммит, "Текущий HEAD уже отличается; раннее наблюдение не восстанавливается задним числом")
        требовать(not гит(корень, "status", "--porcelain=v1", "--untracked-files=all").strip(), "Рабочее дерево уже изменено до начального подтверждения")
        повтор = хранение.Хранилище(корень, задача)._наблюдать_владельца()
        требовать(повтор == владение, "Состояние изменилось во время начального наблюдения")
        хранение.установить(путь, хранение.байты({"данные": запись, "sha256": хранение.хэш(запись)}))
        return запись

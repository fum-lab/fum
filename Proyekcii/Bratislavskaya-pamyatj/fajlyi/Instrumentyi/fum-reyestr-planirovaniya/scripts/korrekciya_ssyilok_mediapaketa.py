"""Подготовить точную коррекцию десяти ссылок; файлы и Git не изменяются."""
import argparse
import hashlib
from pathlib import Path
import re
import sys
import time

sys.dont_write_bytecode = True
from реестр_поддержки import байты, требовать

ФАЙЛЫ = {
    "Журнал/2026-09-15_23-28-08_MSK_создать-локальный-медиапакет-поддержки/запрос.md": 3,
    "Журнал/2026-09-15_23-39-42_MSK_исправить-медиапакет-поддержки/запрос.md": 3,
    "Журнал/2026-09-15_23-54-09_MSK_исправить-финансовое-свидетельство-медиапакета/запрос.md": 4,
}


def исправить(текст, ожидается):
    разделитель = "## Повлиял на файлы\n"
    требовать(текст.count(разделитель) == 1, "Неоднозначный раздел затронутых файлов")
    префикс, раздел = текст.split(разделитель)
    требовать(not re.search(r"(?m)^[ \t]*(?:#{1,2}(?:[ \t]|$)|(?:=+|-+)[ \t]*$)", раздел),
              "После затронутых файлов обнаружена неоднозначная граница раздела")
    образец = r"\]\(\.\./\.\./\.\./\.\./Инструменты/fum-reyestr-(?:planirovaniya|планирования)/(scripts|tests)/([^)\n]+)\)"
    новый, число = re.subn(образец, r"](../../Инструменты/fum-reyestr-planirovaniya/\1/\2)", раздел)
    требовать(число == ожидается, "Неожиданное число исправляемых ссылок")
    return префикс + разделитель + новый


def подготовить(корень):
    исходные = {}
    for имя in ФАЙЛЫ:
        путь = корень / имя
        требовать(путь.is_file() and not путь.is_symlink(), "Нет обычного запроса")
        исходные[имя] = путь.read_text(encoding="utf-8")
    длительности = []
    for номер in range(10):
        начало = time.perf_counter_ns()
        новые = {имя: исправить(текст, ФАЙЛЫ[имя]) for имя, текст in исходные.items()}
        длительности.append(time.perf_counter_ns() - начало)
    изменения = []
    патч = ["*** Begin Patch"]
    for имя, прежде in исходные.items():
        после = новые[имя]
        требовать((корень / имя).read_text(encoding="utf-8") == прежде, "Вход изменился")
        изменения.append({"путь": имя, "ссылок": ФАЙЛЫ[имя], "до_sha256": hashlib.sha256(прежде.encode()).hexdigest(),
                          "после_sha256_до_recency": hashlib.sha256(после.encode()).hexdigest()})
        патч.append("*** Update File: " + имя)
        требовать(len(прежде.splitlines()) == len(после.splitlines()), "Изменилось число строк")
        for старая, новая in zip(прежде.splitlines(), после.splitlines()):
            if старая != новая:
                патч.extend(["@@", "-" + старая, "+" + новая])
    патч.append("*** End Patch")
    return {"схема": "fum.коррекция-ссылок-медиапакета.1", "изменения": изменения, "патч": "\n".join(патч) + "\n",
            "длительности_наносекунды": длительности,
            "исходник_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "граница": "Изменяются только destination в разделе затронутых файлов; цитаты и отчёты сохраняются."}


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--корень-репозитория", required=True)
    аргументы = разбор.parse_args()
    sys.stdout.buffer.write(байты(подготовить(Path(аргументы.корень_репозитория))))

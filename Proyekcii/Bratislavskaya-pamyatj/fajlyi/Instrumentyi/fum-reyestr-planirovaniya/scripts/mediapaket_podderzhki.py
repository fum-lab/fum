"""Черновики поддержки из неизменяемых материалов и явных свидетельств.

Доверие к автору задаёт оператор. Проверка формата и SHA не удостоверяет
личность автора, выполнение описанной проверки или банковскую операцию.
"""
from copy import deepcopy
from datetime import date
import hashlib
import os
from pathlib import Path
import re
import subprocess
import unicodedata

from реестр_поддержки import байты, разобрать, требовать, _заполнить_шаблон

СХЕМА = "fum.вход-медиапакета.2"
ПРЕДЕЛ_БАЙТОВ = 524288
ДЕНЕЖНЫЕ_ПОЛЯ = ("начальный_остаток", "поступления", "комиссии", "возвраты", "расходы")
ПОЛЯ_ИСТОЧНИКА = {"коммит", "путь", "sha256"}
КАТАЛОГ_ШАБЛОНОВ = Path(__file__).resolve().parents[1] / "шаблоны"
ГРАНИЦА_ДОВЕРИЯ = (
    "Оператор явно выбирает доверенного автора. Генератор проверяет формат, "
    "Git-происхождение и согласованность; он не удостоверяет личность автора, "
    "исполнение проверки или банковскую операцию."
)


def _поля(значение, ожидаемые, название):
    требовать(type(значение) is dict and set(значение) == set(ожидаемые), "Неверные поля: " + название)


def _текст(значение, название):
    требовать(type(значение) is str and bool(значение.strip()) and len(значение) <= 8000
              and not any(unicodedata.category(символ) in {"Cc", "Zl", "Zp"} for символ in значение),
              "Нужен непустой однострочный текст: " + название)
    return значение


def _шестнадцатеричный(значение, длина, название):
    требовать(type(значение) is str and re.fullmatch("[0-9a-f]{" + str(длина) + "}", значение),
              "Неверный " + название)


def _проверить_источник(источник, с_цитатой=False):
    _поля(источник, ПОЛЯ_ИСТОЧНИКА | ({"цитата"} if с_цитатой else set()), "источник")
    _шестнадцатеричный(источник["коммит"], 40, "OID")
    _шестнадцатеричный(источник["sha256"], 64, "SHA-256")
    путь = _текст(источник["путь"], "путь")
    требовать(not путь.startswith("/") and "\\" not in путь and ":" not in путь
              and all(часть not in {"", ".", ".."} for часть in путь.split("/")), "Неканонический путь")
    if с_цитатой:
        _текст(источник["цитата"], "цитата")


def _гит(корень, *аргументы):
    среда = {ключ: значение for ключ, значение in os.environ.items() if not ключ.startswith("GIT_")}
    среда.update(GIT_NO_REPLACE_OBJECTS="1", GIT_NO_LAZY_FETCH="1", GIT_TERMINAL_PROMPT="0",
                 GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull, GIT_OPTIONAL_LOCKS="0")
    try:
        return subprocess.check_output(
            ["git", "--no-replace-objects", "--literal-pathspecs", "-c", "protocol.allow=never",
             "-c", "core.hooksPath=" + os.devnull, *аргументы],
            cwd=корень, env=среда, stderr=subprocess.DEVNULL, timeout=10)
    except (OSError, subprocess.SubprocessError) as ошибка:
        raise ValueError("Недоступный локальный Git-объект") from ошибка


def _прочитать_источник(корень, источник, с_цитатой=False):
    _проверить_источник(источник, с_цитатой)
    коммит = источник["коммит"]
    требовать(_гит(корень, "cat-file", "-t", коммит) == b"commit\n", "OID должен указывать на commit")
    # ls-tree не следует по символическим ссылкам; literal-pathspecs запрещает glob.
    запись = _гит(корень, "ls-tree", "-z", "--full-tree", коммит, "--", источник["путь"])
    требовать(запись.count(b"\0") == 1, "Нужен ровно один Git-источник")
    try:
        заголовок, имя = запись[:-1].split(b"\t", 1)
        режим, тип, объект = заголовок.split(b" ")
    except ValueError as ошибка:
        raise ValueError("Неверная запись Git-дерева") from ошибка
    требовать(имя == источник["путь"].encode() and режим in {b"100644", b"100755"} and тип == b"blob",
              "Источник должен быть обычным Git blob с точным путём")
    идентификатор = объект.decode("ascii")
    размер = int(_гит(корень, "cat-file", "-s", идентификатор))
    требовать(0 < размер <= ПРЕДЕЛ_БАЙТОВ, "Недопустимый размер Git-источника")
    содержимое = _гит(корень, "cat-file", "blob", идентификатор)
    требовать(len(содержимое) == размер and hashlib.sha256(содержимое).hexdigest() == источник["sha256"],
              "SHA-256 Git-источника не совпадает")
    if с_цитатой:
        try:
            исходный_текст = содержимое.decode("utf-8")
        except UnicodeError as ошибка:
            raise ValueError("Источник материала должен быть UTF-8") from ошибка
        требовать(источник["цитата"] in исходный_текст, "Цитата отсутствует в материале")
    return содержимое


def _документ(содержимое):
    требовать(type(содержимое) is bytes and 0 < len(содержимое) <= ПРЕДЕЛ_БАЙТОВ, "Размер JSON")
    try:
        # Весь UTF-8 blob: никакого поиска JSON/маркера внутри чужого текста.
        значение = разобрать(содержимое.decode("utf-8"))
    except (UnicodeError, ValueError, RecursionError) as ошибка:
        raise ValueError("Нужен один полный JSON-документ без повторных ключей") from ошибка
    требовать(type(значение) is dict, "Корень JSON должен быть объектом")
    return значение


def _период(значение):
    if значение is None:
        return
    требовать(type(значение) is str and re.fullmatch(r"[0-9]{4}-[0-9]{2}", значение), "Нужен период YYYY-MM")
    try:
        date.fromisoformat(значение + "-01")
    except ValueError as ошибка:
        raise ValueError("Невозможный календарный период") from ошибка


def _суммы(значения):
    _поля(значения, ДЕНЕЖНЫЕ_ПОЛЯ, "суммы")
    for значение in значения.values():
        требовать(значение is None or type(значение) is int and 0 <= значение <= 10**12,
                  "Сумма должна быть целыми неотрицательными копейками либо null")


def _финансы(корень, отчёт):
    _поля(отчёт, {*ДЕНЕЖНЫЕ_ПОЛЯ, "период", "получатель", "валюта", "источник", "доверенный_автор"}, "отчёт")
    _период(отчёт["период"])
    if отчёт["получатель"] is not None:
        _текст(отчёт["получатель"], "получатель")
    требовать(отчёт["валюта"] == "RUB", "Поддерживается только RUB")
    суммы = {ключ: отчёт[ключ] for ключ in ДЕНЕЖНЫЕ_ПОЛЯ}
    _суммы(суммы)
    известны = any(значение is not None for значение in суммы.values())
    if отчёт["источник"] is None:
        требовать(not известны and отчёт["доверенный_автор"] is None, "Числа или автор без финансового свидетельства")
        return None
    автор = _текст(отчёт["доверенный_автор"], "доверенный автор учёта")
    запись = _документ(_прочитать_источник(корень, отчёт["источник"]))
    _поля(запись, {"схема", "вид", "автор", "валюта", "период", "получатель", "суммы"}, "финансовое свидетельство")
    требовать(запись["схема"] == "fum.свидетельство-поддержки.1" and запись["вид"] == "фактический учёт",
              "Нужно явное свидетельство фактического учёта")
    требовать(_текст(запись["автор"], "автор учёта") == автор, "Автор учёта не совпадает с выбранным")
    _суммы(запись["суммы"])
    _период(запись["период"])
    if запись["получатель"] is not None:
        _текст(запись["получатель"], "получатель свидетельства")
    требовать(not известны or запись["период"] is not None and запись["получатель"] is not None,
              "Известные суммы требуют периода и получателя")
    требовать(запись["валюта"] == "RUB" and запись["суммы"] == суммы
              and all(запись[ключ] == отчёт[ключ] for ключ in ("период", "получатель", "валюта")),
              "Отчёт не совпадает с финансовым свидетельством, включая null")
    return запись


def _результат(корень, результат):
    _поля(результат, {"вид", "источник", "основание"}, "результат")
    требовать(результат["вид"] in ("план", "материал", "проверенный результат"), "Неизвестный вид результата")
    _прочитать_источник(корень, результат["источник"], с_цитатой=True)
    if результат["вид"] != "проверенный результат":
        требовать(результат["основание"] is None, "План и материал не принимают основание проверки")
        return None
    основание = результат["основание"]
    _поля(основание, {"источник", "доверенный_автор"}, "основание результата")
    автор = _текст(основание["доверенный_автор"], "доверенный автор результата")
    запись = _документ(_прочитать_источник(корень, основание["источник"]))
    _поля(запись, {"схема", "вид", "автор", "объект", "утверждение", "проверка", "исход", "протокол"},
           "свидетельство результата")
    требовать(запись["схема"] == "fum.свидетельство-результата.1" and запись["вид"] == "свидетельство проверки",
              "Нужно свидетельство проверки")
    _проверить_источник(запись["объект"])
    объект = {ключ: результат["источник"][ключ] for ключ in ПОЛЯ_ИСТОЧНИКА}
    требовать(запись["объект"] == объект and запись["утверждение"] == результат["источник"]["цитата"],
              "Свидетельство относится к другому объекту или утверждению")
    требовать(_текст(запись["автор"], "автор результата") == автор and запись["исход"] == "успешно",
              "Нет успешного свидетельства выбранного автора")
    _текст(запись["проверка"], "граница проверки")
    _прочитать_источник(корень, запись["протокол"])
    return запись


def _адрес(источник):
    return источник["коммит"] + ":" + источник["путь"] + " (SHA-256 " + источник["sha256"] + ")"


def _деньги(значение):
    if значение is None:
        return "неизвестно"
    знак = "-" if значение < 0 else ""
    значение = abs(значение)
    return f"{знак}{значение // 100},{значение % 100:02d} ₽"


def _шаблон(имя, значения):
    путь = КАТАЛОГ_ШАБЛОНОВ / имя
    требовать(путь.is_file() and not путь.is_symlink() and not КАТАЛОГ_ШАБЛОНОВ.is_symlink(), "Нет обычного шаблона")
    шаблон = путь.read_text(encoding="utf-8")
    поля = re.findall(r"\{\{([^{}]+)\}\}", шаблон)
    требовать(len(поля) == len(set(поля)) and set(поля) == set(значения), "Повреждён контракт шаблона")
    остаток = re.sub(r"\{\{[^{}]+\}\}", "", шаблон)
    требовать("{{" not in остаток and "}}" not in остаток, "Повреждён маркер шаблона")
    return _заполнить_шаблон(шаблон, значения)


def собрать(корень, данные):
    _поля(данные, {"схема", "лицензия", "результат", "ограничения", "цель", "следующий_шаг", "отчёт"}, "вход")
    данные = deepcopy(данные)
    требовать(данные["схема"] == СХЕМА, "Нужна явная миграция к fum.вход-медиапакета.2")
    требовать(данные["лицензия"] == "CC0-1.0", "Нужна CC0-1.0")
    требовать(type(данные["ограничения"]) is list and 0 < len(данные["ограничения"]) <= 32, "Нужны ограничения")
    for ограничение in данные["ограничения"]:
        _текст(ограничение, "ограничение")
    _текст(данные["цель"], "цель")
    _текст(данные["следующий_шаг"], "следующий шаг")
    корень = Path(корень)
    свидетельство = _результат(корень, данные["результат"])
    учёт = _финансы(корень, данные["отчёт"])
    вид = данные["результат"]["вид"]
    метка = {"план": "План", "материал": "Материал", "проверенный результат": "Результат по свидетельству"}[вид]
    источник = данные["результат"]["источник"]
    основание = "Основание проверки: отсутствует; утверждение не объявлено проверенным."
    if свидетельство is not None:
        основание = ("Автор свидетельства: " + свидетельство["автор"] + ". Проверка: " + свидетельство["проверка"]
                     + "\nСвидетельство: " + _адрес(данные["результат"]["основание"]["источник"])
                     + "\nПротокол: " + _адрес(свидетельство["протокол"]))
    основа = _шаблон("сообщение-поддержки.шаблон.txt", {
        "метка": метка, "цитата": источник["цитата"], "источник": _адрес(источник),
        "основание": основание, "ограничения": "; ".join(данные["ограничения"]),
        "цель": данные["цель"], "следующий_шаг": данные["следующий_шаг"], "доверие": ГРАНИЦА_ДОВЕРИЯ})
    отчёт = данные["отчёт"]
    остаток = None
    if all(отчёт[ключ] is not None for ключ in ДЕНЕЖНЫЕ_ПОЛЯ):
        остаток = отчёт["начальный_остаток"] + отчёт["поступления"] - отчёт["комиссии"] - отчёт["возвраты"] - отчёт["расходы"]
    строки = ["Период: " + (отчёт["период"] or "неизвестно"), "Получатель: " + (отчёт["получатель"] or "неизвестно"),
              "Валюта: RUB"]
    подписи = ("Начальный остаток", "Поступления", "Комиссии", "Возвраты", "Расходы")
    строки.extend(подпись + ": " + _деньги(отчёт[ключ]) for подпись, ключ in zip(подписи, ДЕНЕЖНЫЕ_ПОЛЯ))
    строки.append("Конечный остаток: " + _деньги(остаток))
    финансовое_основание = "Финансовое свидетельство: отсутствует"
    if учёт is not None:
        финансовое_основание = "Финансовое свидетельство: " + _адрес(отчёт["источник"]) + "\nАвтор учёта: " + учёт["автор"]
    черновик_отчёта = _шаблон("отчёт-поддержки.шаблон.txt",
                              {"строки": "\n".join(строки), "основание": финансовое_основание, "доверие": ГРАНИЦА_ДОВЕРИЯ})
    return {"схема": "fum.выход-медиапакета.2", "вход_sha256": hashlib.sha256(байты(данные)).hexdigest(),
            "источники": {"материал": источник, "основание_результата": данные["результат"]["основание"],
                          "финансовое_свидетельство": отчёт["источник"]}, "граница_доверия": ГРАНИЦА_ДОВЕРИЯ,
            "черновики": {"Telegram": "Черновик Telegram\n\n" + основа, "MAX": "Черновик MAX\n\n" + основа,
                          "отчёт": черновик_отчёта}, "конечный_остаток_копейки": остаток}


def прочитать_вход(путь):
    with Path(путь).open("rb") as поток:
        содержимое = поток.read(ПРЕДЕЛ_БАЙТОВ + 1)
    return _документ(содержимое)

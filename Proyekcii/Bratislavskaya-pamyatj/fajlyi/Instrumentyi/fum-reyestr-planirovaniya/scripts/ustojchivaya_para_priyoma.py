"""Отдельное свидетельство только штатного изменения навигации принятого запроса."""
import copy
import hashlib
from pathlib import Path

import вход_направления as вход
import приём_направления as хранение
import устойчивые_свидетельства as устойчивые


def проверить_исходные(запись, проверить_пару):
    for свидетельство in запись["свидетельства"].values():
        вход.обработка.фрагмент(свидетельство, запись["файлы"][свидетельство["путь"]].encode("utf-8"))
    for имя in {свидетельство["путь"] for свидетельство in запись["свидетельства"].values()}:
        проверить_пару(запись, имя, запись["файлы"][имя].encode("utf-8"))


def построить(запись, пути, прочитать, проверить_пару):
    """Новые позиции выводятся из прежнего снимка, а не принимаются от вызывающего."""
    проверить_исходные(запись, проверить_пару)
    запрос = запись["запрос"]
    прежнее = запись["файлы"][запрос]
    текущее = прочитать(запрос).decode("utf-8")
    структура = вход.структура
    папки = sorted(Path(путь).parent.name for путь in пути
        if len(Path(путь).parts) == 3 and Path(путь).parts[0] == "Журнал"
        and Path(путь).name == "запрос.md"
        and структура.SESSION_PATTERN.fullmatch(Path(путь).parent.name))
    папка = Path(запрос).parent.name
    хранение.требовать(папки.count(папка) == 1, "Неоднозначный запрос принятой пары")
    место = папки.index(папка)
    предыдущий = папки[место - 1] if место else None
    следующий = папки[место + 1] if место + 1 < len(папки) else None
    try:
        подписи = {имя: структура._request_heading_label(
            прочитать("Журнал/" + имя + "/запрос.md").decode("utf-8"), имя)
            for имя in (предыдущий, следующий) if имя is not None}
        ожидаемое = структура._replace_navigation(прежнее, предыдущий, следующий, подписи)
    except структура.LayoutError as ошибка:
        raise хранение.ОшибкаПриёма("Нет проверяемой штатной навигации принятой пары") from ошибка
    маркер = "<!-- FUM-INTAKE: " + запись["экземпляр"] + " -->"
    хранение.требовать(прежнее.count(маркер) == текущее.count(маркер) == 1,
        "Неоднозначный исходный блок принятой пары")
    до = прежнее.index(маркер)
    после = текущее.index(маркер)
    хранение.требовать(ожидаемое[:ожидаемое.index(маркер)] == текущее[:после],
        "Перед принятой парой изменена не только штатная навигация")
    старое = запись["свидетельства"]["команда"]
    исходные_байты = вход.обработка.фрагмент(старое, прежнее.encode("utf-8"))
    сдвиг = len(текущее[:после].encode("utf-8")) - len(прежнее[:до].encode("utf-8"))
    новое = {**старое, "начало": старое["начало"] + сдвиг, "конец": старое["конец"] + сдвиг}
    хранение.требовать(сдвиг != 0, "Устойчивое соответствие не требуется без сдвига навигации")
    кандидат = copy.deepcopy(запись)
    кандидат["свидетельства"]["команда"] = новое
    # Сохраняются прежний каркас, UUID, раздел, единственность и открытая разметка.
    проверить_пару(кандидат, запрос, текущее.encode("utf-8"))
    отчёт = str(Path(запрос).with_name("отчёт.md"))
    проверить_пару(запись, отчёт, прочитать(отчёт))
    событие = хранение.хэш({"задача": запись["источник"], "экземпляр": запись["экземпляр"]})
    соответствие = {"схема": "fum.устойчивая-пара-приёма.1", "событие": событие,
        "задача": запись["задача"], "источник": запись["источник"], "экземпляр": запись["экземпляр"],
        "база": запись["база"], "решение_sha256": хранение.хэш(запись["решение"]),
        "исходный_план_sha256": хранение.хэш(запись["файлы"]),
        "прежние_свидетельства": copy.deepcopy(запись["свидетельства"]),
        "свидетельства": copy.deepcopy(кандидат["свидетельства"]),
        "навигация": {"предыдущий": предыдущий, "следующий": следующий, "подписи": подписи},
        "прежний_префикс_sha256": hashlib.sha256(прежнее[:до].encode()).hexdigest(),
        "новый_префикс_sha256": hashlib.sha256(текущее[:после].encode()).hexdigest()}
    поколение = хранение.хэш(соответствие)
    каталог = str(Path(запрос).parent / "материалы/устойчивая-пара" / событие / поколение)
    имя_команды = каталог + "/команда.txt"
    соответствие["устойчивая_команда"] = устойчивые.свидетельство(имя_команды, исходные_байты)
    файлы = [{"путь": имя_команды, "текст": исходные_байты.decode("utf-8"),
        "sha256": hashlib.sha256(исходные_байты).hexdigest()}]
    данные = хранение.байты(соответствие)
    файлы.append({"путь": каталог + "/соответствие.json", "текст": данные.decode("utf-8"),
        "sha256": hashlib.sha256(данные).hexdigest()})
    return кандидат, файлы

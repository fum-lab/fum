import uuid

from приём_направления import требовать, безопасный_путь, ОшибкаПриёма
from доставка_гит import выполнить, гит, защищённые_файлы

ИНСТРУМЕНТЫ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ИНСТРУМЕНТЫ / "fum-otchyotyi-o-zapuskakh-proverok" / "scripts"))
import отчёты_о_запусках_проверок as отчёты


def загрузить_связность():
    имя = "связность_для_доставки"
    if имя not in sys.modules:
        описание = importlib.util.spec_from_file_location(имя, ИНСТРУМЕНТЫ / "fum-svyaznostj-rabochej-sessii/scripts/check-session-coherence.py")
        модуль = importlib.util.module_from_spec(описание)
        sys.modules[имя] = модуль
        описание.loader.exec_module(модуль)
    return sys.modules[имя]


def отпечаток(путь):
    безопасный_путь(путь)
    сведения = путь.lstat()
    требовать(stat.S_ISREG(сведения.st_mode), "Служебный путь должен быть обычным файлом")
    return {"режим": сведения.st_mode, "sha256": hashlib.sha256(путь.read_bytes()).hexdigest()}


def дерево(корень, объект):
    итог = {}
    for строка in выполнить(корень, "ls-tree", "-r", "-z", объект).stdout.split(b"\0"):
        if строка:
            сведения, имя = строка.split(b"\t", 1)
            режим, _, оид = сведения.decode().split()
            итог[имя.decode()] = {"режим": режим, "объект": оид}
    return итог


def файлы(корень):
    итог = защищённые_файлы(корень)
    for строка in выполнить(корень, "ls-files", "--stage", "-z").stdout.split(b"\0"):
        if строка:
            сведения, имя = строка.split(b"\t", 1)
            if not сведения.startswith(b"160000 "):
                итог[имя.decode()] = отпечаток(корень / имя.decode())
            elif (корень / имя.decode() / ".git").exists():
                for вложенное, значение in файлы(корень / имя.decode()).items():
                    итог[имя.decode() + "/" + вложенное] = значение
    return итог


def история(корень, запрос, *, пустой=False):
    try:
        return _история(корень, запрос, пустой=пустой)
    except отчёты.ОшибкаОтчёта as ошибка:
        raise ОшибкаПриёма(str(ошибка)) from ошибка


def _история(корень, запрос, *, пустой):
    _, _, путь, каталог, сессия = отчёты.разрешить_сессию(корень, запрос)
    with отчёты.межпроцессная_блокировка(корень, сессия):
        отчёты.запретить_действие_при_возобновлении(каталог, "доставка")
        требовать(not (каталог / отчёты.ИМЯ_СНИМКА).exists(), "Доставке нужен открытый отчёт")
        записи = [] if пустой and (not каталог.exists() or not any(каталог.iterdir())) else отчёты.прочитать_историю_проверок(каталог, сессия)
        требовать(all(запись["состояние"] == "завершён" for _, запись, _ in записи), "Есть незавершённая проверка")
        требовать(отчёты.границы_управляемого_блока(путь.read_text())[2] == отчёты.ОТКРЫТЫЙ_МАРКЕР, "Нужен открытый marker")
    return путь, каталог, сессия, записи


def подготовить(корень, запрос, задача, дерево_слияния, команда, тайм_аут):
    путь, каталог, сессия, записи = история(корень, запрос, пустой=True)
    корневая, ошибки = загрузить_связность().codex_thread_id_from_request((корень / сессия).read_text())
    требовать(not ошибки and корневая == задача, "Запрос относится к другой корневой задаче")
    состав = дерево(корень, дерево_слияния)
    имена = [сессия, str(путь.relative_to(корень)), *(str(имя.relative_to(корень)) for имя, _, _ in записи)]
    требовать(all(имя in состав for имя in имена), "Запрос, отчёт и прежние записи должны входить в дерево слияния")
    идентификатор = str(uuid.uuid4())
    запуск = [sys.executable, "-B", str(Path(отчёты.__file__).resolve()), "запустить", "--корень-репозитория", str(корень),
              "--запрос", сессия, "--название", "Проверка обратной доставки", "--исполнитель", "Владелец доставки",
              "--идентификатор-запуска", идентификатор, "--класс-проверки", "адресная",
              "--тайм-аут-секунды", str(тайм_аут), "--", *команда]
    return {"запрос": сессия, "корневая_задача": задача, "дерево_слияния": дерево_слияния,
            "отчёт": str(путь.relative_to(корень)), "исходный_отчёт": путь.read_bytes().decode(),
            "файлы": файлы(корень), "прежние": [str(имя.relative_to(корень)) for имя, _, _ in записи],
            "запуск": идентификатор, "команда": запуск, "разница": None}


def сверить(корень, граница, *, предпросмотр=False, итоговый=False):
    путь, каталог, сессия, записи = история(корень, граница["запрос"])
    новые = [(имя, запись) for имя, запись, _ in записи if str(имя.relative_to(корень)) not in граница["прежние"]]
    требовать(len(новые) == 1 and новые[0][1]["идентификатор"] == граница["запуск"], "Нет единственного назначенного терминала")
    имя_запуска = str(новые[0][0].relative_to(корень))
    разрешены = {граница["отчёт"], имя_запуска}
    текущие = файлы(корень)
    требовать(set(текущие) == set(граница["файлы"]) | {имя_запуска}, "Появились или исчезли посторонние файлы")
    требовать(all(текущие[имя] == значение for имя, значение in граница["файлы"].items() if имя not in разрешены), "Изменились байты вне служебной разницы")
    требовать(текущие[граница["отчёт"]]["режим"] == граница["файлы"][граница["отчёт"]]["режим"], "Изменился режим отчёта")
    разница = {имя: отпечаток(корень / имя) for имя in sorted(разрешены)}
    if итоговый:
        требовать(разница == граница["разница"], "Коммит содержит другие служебные байты")
        return разница, новые[0][1]
    контекст, содержимое = отчёты.текущий_контекст_проверок(корень, сессия, записи)
    ожидаемое = отчёты.заменить_управляемый_блок_в_байтах(граница["исходный_отчёт"].encode(),
        отчёты.сформировать_блок_истории(записи, отчёты.ОТКРЫТЫЙ_МАРКЕР, контекст, содержимое))
    if предпросмотр:
        требовать(путь.read_bytes() in (граница["исходный_отчёт"].encode(), ожидаемое), "Отчёт изменён вне штатного renderer")
        отчёты.выполнить_предпросмотр(корень, Path(сессия))
    требовать(путь.read_bytes() == ожидаемое, "Отчёт не равен точному штатному renderer")
    разница = {имя: отпечаток(корень / имя) for имя in sorted(разрешены)}
    требовать(граница["разница"] in (None, разница), "Изменились принятые служебные байты")
    return разница, новые[0][1]


def сверить_дерево(корень, граница, итоговое):
    ожидаемое = дерево(корень, граница["дерево_слияния"])
    for имя, сведения in граница["разница"].items():
        ожидаемое[имя] = {"режим": "100755" if сведения["режим"] & 0o111 else "100644",
                            "объект": гит(корень, "hash-object", "--no-filters", "--", имя)}
    требовать(дерево(корень, итоговое) == ожидаемое, "Индекс не равен слиянию плюс принятой служебной разнице")

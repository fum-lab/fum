#!/usr/bin/env python3
"""Одноразовые команды сохраняемого приёма; внешние возможности даёт Codex."""
import argparse
import json
from pathlib import Path
import sys

import исполнитель_приёма as исполнение
import постановка_задачи as постановка
import приём_направления as хранение


def прочитать(имя):
    путь = Path(имя).absolute()
    хранение.безопасный_путь(путь)
    return хранение.разобрать(исполнение.вход.обработка.прочитать_файл(путь))


def выполнить(параметры):
    корень = Path(параметры.корень_репозитория).resolve()
    if параметры.команда == "подтвердить-начало":
        return постановка.подтвердить_начало(корень, параметры.задача, параметры.коммит, параметры.источник)
    исполнитель = исполнение.ИсполнительПриёма(корень, параметры.задача)
    if параметры.команда == "исправить-отображение-основания":
        import отображение_основания
        return отображение_основания.поправить(корень, параметры.задача, прочитать(параметры.поправка))
    if параметры.команда == "исправить-план":
        return исполнитель.исправить_план(прочитать(параметры.исправление))
    if параметры.команда == "закрепить":
        return исполнитель.закрепить_постановку(параметры.событие, параметры.коммит, параметры.ветка)
    if параметры.команда == "сохранить":
        return исполнитель.сохранить_ответ(параметры.событие, параметры.попытка, прочитать(параметры.ответ))
    if параметры.команда == "наблюдать":
        return исполнитель.наблюдать(параметры.событие, Path(параметры.корень_задачи), параметры.идентификатор_задачи, параметры.источник)
    вход = прочитать(параметры.вход)
    хранение.поля(вход, {"источник", "исходная_задача", "решение", "запрос", "карточки", "номера"})
    if параметры.команда == "подготовить":
        return исполнитель.подготовить(вход["источник"], вход["исходная_задача"], вход["решение"], вход["запрос"], вход["карточки"], номера=вход["номера"])
    return исполнитель.допустить_вызов(вход["источник"], вход["исходная_задача"], вход["решение"])


def главный(аргументы=None):
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--корень-репозитория", required=True)
    парсер.add_argument("--задача", required=True)
    команды = парсер.add_subparsers(dest="команда", required=True)
    for имя in ("подготовить", "допустить"):
        команда = команды.add_parser(имя)
        команда.add_argument("--вход", required=True)
    команда = команды.add_parser("исправить-отображение-основания")
    команда.add_argument("--поправка", required=True)
    команда = команды.add_parser("исправить-план")
    команда.add_argument("--исправление", required=True)
    команда = команды.add_parser("закрепить")
    команда.add_argument("--событие", required=True)
    команда.add_argument("--коммит", required=True)
    команда.add_argument("--ветка", required=True)
    команда = команды.add_parser("сохранить")
    команда.add_argument("--событие", required=True)
    команда.add_argument("--попытка", required=True)
    команда.add_argument("--ответ", required=True)
    for имя in ("подтвердить-начало", "наблюдать"):
        команда = команды.add_parser(имя)
        команда.add_argument("--источник", required=True)
        if имя == "подтвердить-начало":
            команда.add_argument("--коммит", required=True)
        else:
            команда.add_argument("--событие", required=True)
            команда.add_argument("--корень-задачи", required=True)
            команда.add_argument("--идентификатор-задачи", required=True)
    параметры = парсер.parse_args(аргументы)
    try:
        результат = выполнить(параметры)
    except (ValueError, OSError, UnicodeError) as ошибка:
        print(json.dumps({"схема": "fum.отказ-приёма.1", "ошибка": str(ошибка)}, ensure_ascii=False), file=sys.stderr)
        return 2
    print(json.dumps(результат, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(главный())

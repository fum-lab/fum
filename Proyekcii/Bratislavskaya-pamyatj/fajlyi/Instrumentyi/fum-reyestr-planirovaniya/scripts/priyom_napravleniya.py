class ОшибкаПриёма(ValueError):
    pass


def требовать(условие, пояснение):
    if not условие:
        raise ОшибкаПриёма(пояснение)


def байты(значение):
    try:
        return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode("utf-8")
    except (TypeError, ValueError, UnicodeError) as ошибка:
        raise ОшибкаПриёма("Значение не представимо допустимым JSON") from ошибка


def хэш(значение):
    return hashlib.sha256(байты(значение)).hexdigest()


def текст(значение):
    return isinstance(значение, str) and bool(значение.strip()) and not any(ord(знак) < 32 for знак in значение)


def разобрать(данные):
    def пары(элементы):
        итог = {}
        for ключ, значение in элементы:
            требовать(ключ not in итог, "Повтор JSON-поля")
            итог[ключ] = значение
        return итог
    def константа(имя):
        raise ОшибкаПриёма("Недопустимая числовая константа JSON")
    try:
        return json.loads(данные, object_pairs_hook=пары, parse_constant=константа)
    except (ValueError, UnicodeError) as ошибка:
        raise ОшибкаПриёма("Повреждён JSON") from ошибка


def проверить_структуру_данных(значение):
    if значение is None or type(значение) in (bool, int, str):
        байты(значение)
    elif type(значение) is float:
        требовать(math.isfinite(значение), "Недопустимое число JSON")
    elif type(значение) is list:
        for элемент in значение:
            проверить_структуру_данных(элемент)
    elif type(значение) is dict:
        требовать(all(type(ключ) is str for ключ in значение), "JSON требует строковые ключи")
        for элемент in значение.values():
            проверить_структуру_данных(элемент)
    else:
        raise ОшибкаПриёма("Неизвестный тип JSON")


def поля(значение, имена):
    требовать(type(значение) is dict and set(значение) == set(имена), "Неизвестные либо отсутствующие поля записи")


def шестнадцатеричный(значение, длина=64):
    return isinstance(значение, str) and re.fullmatch(r"[0-9a-f]{" + str(длина) + "}", значение) is not None


def идентификатор_задачи(значение):
    return isinstance(значение, str) and re.fullmatch(r"[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}", значение) is not None


def номер_карточки(значение):
    return isinstance(значение, str) and re.fullmatch(r"FUM-(?:STEP|REQ|СБОЙ)-[0-9]{4}", значение) is not None


def абсолютный_корень(значение):
    return текст(значение) and Path(значение).is_absolute() and Path(значение).as_posix() == значение and ".." not in Path(значение).parts


def ветка_писателя(значение):
    return текст(значение) and значение.startswith("refs/heads/codex/") and len(значение) > len("refs/heads/codex/")


def путь_результата(имя):
    требовать(текст(имя), "Нужен путь результата")
    путь = Path(имя)
    область = len(путь.parts) > 1 and путь.parts[0] in {"Журнал", "Планирование", "Требования"}
    if len(путь.parts) == 2 and путь.parts[0] == "Сбои":
        область = путь.name == "README.md" or re.fullmatch(r"FUM-СБОЙ-[0-9]{4}-[^/]+\.md", путь.name) is not None
    требовать(not путь.is_absolute() and ".." not in путь.parts and путь.as_posix() == имя and область, "Недопустимый путь результата")
    return путь


def ключ_этапа(событие, этап):
    требовать(текст(событие) and текст(этап), "Нужна точная пара события и этапа")
    return хэш({"событие": событие, "этап": этап})


def состояние_ответа(ответ):
    if isinstance(ответ, dict):
        if идентификатор_задачи(ответ.get("threadId")) and текст(ответ.get("hostId")):
            return "требуется наблюдение задачи"
        if текст(ответ.get("clientThreadId")):
            return "ожидается taskID"
    return "исход неизвестен"


def проверить_состояние(состояние, общий):
    поля(состояние, {"схема", "база", "резервы", "попытки", "писатели", "этапы", "занятые", "импорт", "история", "приёмы"})
    требовать(состояние["схема"] == "fum.приём-направлений.1" and состояние["база"] == str(общий), "Чужая база состояния")
    проверить_структуру_данных(состояние)
    for имя in ("резервы", "попытки", "писатели", "этапы", "импорт", "приёмы"):
        требовать(type(состояние[имя]) is dict, "Нужен словарь: " + имя)
    требовать(состояние["история"] is None or шестнадцатеричный(состояние["история"]), "Неверный отпечаток истории")
    занятые = состояние["занятые"]
    требовать(type(занятые) is list and all(номер_карточки(номер) for номер in занятые) and занятые == sorted(set(занятые)), "Неверный вечный набор номеров")
    владельцы = set()
    for событие, запись in состояние["резервы"].items():
        поля(запись, {"номера", "основание", "refs_sha256"})
        требовать(текст(событие) and текст(запись["основание"]) and шестнадцатеричный(запись["refs_sha256"]), "Неверное происхождение резерва")
        номера = запись["номера"]
        требовать(type(номера) is dict and номера and set(номера) <= ВИДЫ_НОМЕРОВ, "Неверные виды резерва")
        for вид, номер in номера.items():
            требовать(номер_карточки(номер) and номер.rsplit("-", 1)[0] == вид and номер in занятые and номер not in владельцы, "Потерянный номер либо конфликт владельцев")
            владельцы.add(номер)
    for основание, номера in состояние["импорт"].items():
        требовать(текст(основание) and type(номера) is list and номера and all(номер_карточки(номер) for номер in номера) and номера == sorted(set(номера)) and set(номера) <= set(занятые), "Неверный импорт резерва")
    ветки = set()
    for корень, запись in состояние["писатели"].items():
        поля(запись, {"задача", "ref"})
        требовать(абсолютный_корень(корень) and идентификатор_задачи(запись["задача"]) and ветка_писателя(запись["ref"]) and запись["ref"] not in ветки, "Неверное либо повторное владение деревом")
        ветки.add(запись["ref"])
    def владелец(запись):
        требовать(идентификатор_задачи(запись["задача"]) and абсолютный_корень(запись["корень"]) and ветка_писателя(запись["ref"]) and шестнадцатеричный(запись["база"], 40), "Неверный владелец и база записи")
        требовать(состояние["писатели"].get(запись["корень"]) == {"задача": запись["задача"], "ref": запись["ref"]}, "Запись не связана с владельцем дерева")
    for событие, запись in состояние["попытки"].items():
        поля(запись, {"попытка", "аргументы", "аргументы_sha256", "состояние", "ответ", "задача", "корень", "ref", "база"})
        владелец(запись)
        требовать(текст(событие) and идентификатор_задачи(запись["попытка"]) and type(запись["аргументы"]) is dict and запись["аргументы"], "Неверная внешняя попытка")
        требовать(запись["аргументы_sha256"] == хэш(запись["аргументы"]), "Подменены аргументы попытки")
        требовать(запись["ответ"] is None or type(запись["ответ"]) is dict, "Неверный ответ попытки")
        требовать(запись["состояние"] == состояние_ответа(запись["ответ"]), "Состояние не соответствует ответу")
    for ключ, запись in состояние["этапы"].items():
        поля(запись, {"событие", "этап", "задача", "корень", "ref", "база", "файлы", "готов", "коммит"})
        владелец(запись)
        требовать(ключ == ключ_этапа(запись["событие"], запись["этап"]), "Неоднозначный ключ этапа")
        требовать(type(запись["готов"]) is bool and (запись["коммит"] is None or (запись["готов"] and шестнадцатеричный(запись["коммит"], 40))), "Неверная готовность либо квитанция этапа")
        требовать(type(запись["файлы"]) is dict and запись["файлы"], "Пустой план этапа")
        for имя, изменение in запись["файлы"].items():
            путь_результата(имя)
            поля(изменение, {"до", "после"})
            требовать((изменение["до"] is None or type(изменение["до"]) is str) and type(изменение["после"]) is str, "Неверные байты плана")


def гит(корень, *аргументы, вход=None, сырые=False):
    среда = {ключ: значение for ключ, значение in os.environ.items() if not ключ.startswith("GIT_")}
    среда["GIT_OPTIONAL_LOCKS"] = "0"
    процесс = subprocess.run(["git", "--no-replace-objects", "-c", "core.quotepath=false", *аргументы], cwd=корень, env=среда, input=вход, capture_output=True)
    требовать(процесс.returncode == 0, "Не удалось прочитать Git: " + аргументы[0])
    return процесс.stdout if сырые else процесс.stdout.decode("utf-8")


def идентичности_карточки(путь, содержимое):
    """Объявления карточки, а не ссылки, примеры и текст её критериев."""
    имя = Path(путь)
    if имя.suffix != ".md" or имя.name == "README.md":
        return set()
    номера = set()
    if путь.startswith("Планирование/карточки-шагов/") or путь.startswith("Сбои/"):
        вид = "FUM-STEP" if путь.startswith("Планирование/карточки-шагов/") else "FUM-СБОЙ"
        поле = "card_id" if вид == "FUM-STEP" else "идентификатор_сбоя"
        совпадение = re.match(r"^(?:(?:🟡|✅|🧩|🗑️)-)?(" + вид + r"-[0-9]{4})(?=-|\.md$)", имя.name)
        if совпадение:
            номера.add(совпадение[1])
        начало = re.match(r"\A\+\+\+\r?\n(.*?)\r?\n\+\+\+(?:\r?\n|\Z)", содержимое, re.S)
        if начало:
            try:
                метаданные = tomllib.loads(начало[1])
            except tomllib.TOMLDecodeError as ошибка:
                raise ОшибкаПриёма("Неразбираемые метаданные исторической карточки: " + путь) from ошибка
            номер = метаданные.get(поле)
            if номер is not None:
                требовать(номер_карточки(номер) and номер.rsplit("-", 1)[0] == вид, "Неверная идентичность исторической карточки")
                номера.add(номер)
    elif путь.startswith("Требования/"):
        ограда = None
        for строка in содержимое.splitlines():
            граница = re.match(r"^ {0,3}(`{3,}|~{3,})", строка)
            if граница:
                if ограда is None:
                    ограда = граница[1]
                elif граница[1][0] == ограда[0] and len(граница[1]) >= len(ограда):
                    ограда = None
                continue
            совпадение = re.fullmatch(r"<!--\s*FUM-REQUIREMENT-ID:\s*(FUM-REQ-[0-9]{4})\s*-->\s*", строка)
            if ограда is None and совпадение:
                номера.add(совпадение[1])
    return номера


def безопасный_путь(путь, *, каталог=False):
    for часть in [*reversed(путь.parents), путь]:
        if часть.exists() or часть.is_symlink():
            состояние = часть.lstat()
            требовать(not stat.S_ISLNK(состояние.st_mode), "Символическая ссылка в пути")
    if путь.exists():
        состояние = путь.stat()
        требовать(stat.S_ISDIR(состояние.st_mode) if каталог else stat.S_ISREG(состояние.st_mode), "Неверный тип пути")
        if not каталог:
            требовать(состояние.st_nlink == 1, "Жёсткая ссылка в пути")


def синхронизировать_каталог(путь):
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def создать_каталоги(путь, граница, права=0o755):
    требовать(путь == граница or граница in путь.parents, "Каталог вне границы")
    безопасный_путь(путь, каталог=True)
    цепочка = []
    текущий = путь
    while текущий != граница:
        цепочка.append(текущий)
        текущий = текущий.parent
    for каталог in reversed(цепочка):
        каталог.mkdir(mode=права, exist_ok=True)
        безопасный_путь(каталог, каталог=True)
    # Повтор после прерывания также синхронизирует уже созданных предков.
    for каталог in [*цепочка, граница]:
        синхронизировать_каталог(каталог)


def установить(путь, данные):
    безопасный_путь(путь)
    дескриптор, имя = tempfile.mkstemp(prefix=".приём-", dir=путь.parent)
    try:
        with os.fdopen(дескриптор, "wb") as поток:
            поток.write(данные)
            поток.flush()
            os.fsync(поток.fileno())
        os.replace(имя, путь)
        синхронизировать_каталог(путь.parent)
    finally:
        if os.path.exists(имя):
            os.unlink(имя)


class Хранилище:
    def __init__(сам, корень, задача):
        безопасный_путь(Path(корень).absolute(), каталог=True)
        сам.корень = Path(корень).resolve()
        требовать(re.fullmatch(r"[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}", задача), "Нужен настоящий UUID корневой задачи")
        сам.задача = задача
        требовать(Path(гит(сам.корень, "rev-parse", "--show-toplevel").strip()).resolve() == сам.корень, "Нужен физический корень checkout")
        сам.общий = Path(гит(сам.корень, "rev-parse", "--path-format=absolute", "--git-common-dir").strip())
        сам.каталог = сам.общий / "fum-приём-направлений-v1"
        сам.путь = сам.каталог / "состояние.json"
        сам.профиль = []
        сам._замок_удержан = False

    def прочитать(сам):
        """Согласованный снимок без mkdir, O_CREAT, замка или инициализации."""
        безопасный_путь(сам.каталог, каталог=True)
        безопасный_путь(сам.путь)
        маркер = сам.каталог / "инициализирован"
        безопасный_путь(маркер)
        if сам.каталог.exists():
            требовать(сам.каталог.stat().st_uid == os.getuid(), "Чужой владелец состояния")
        if not сам.путь.exists():
            требовать(not маркер.exists(), "Исчезнувший журнал требует восстановления")
            return {"схема": "fum.приём-направлений.1", "база": str(сам.общий), "резервы": {}, "попытки": {}, "писатели": {}, "этапы": {}, "занятые": [], "импорт": {}, "история": None, "приёмы": {}}
        def прочесть(путь):
            with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
                требовать(os.fstat(поток.fileno()).st_uid == os.getuid(), "Чужой владелец файла состояния")
                return разобрать(поток.read())
        требовать(маркер.exists() and прочесть(маркер) == {"база": str(сам.общий)}, "Потерян либо повреждён маркер инициализации")
        конверт = прочесть(сам.путь)
        поля(конверт, {"данные", "sha256"})
        требовать(конверт["sha256"] == хэш(конверт["данные"]), "Повреждён хэш состояния")
        проверить_состояние(конверт["данные"], сам.общий)
        return конверт["данные"]

    @contextmanager
    def изменить(сам):
        начало = time.monotonic_ns()
        безопасный_путь(сам.каталог, каталог=True)
        создать_каталоги(сам.каталог, сам.общий, 0o700)
        требовать(сам.каталог.stat().st_uid == os.getuid(), "Чужой владелец состояния")
        замок = сам.каталог / "замок"
        безопасный_путь(замок)
        with os.fdopen(os.open(замок, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600), "r+b") as поток:
            fcntl.flock(поток, fcntl.LOCK_EX)
            безопасный_путь(сам.путь)
            начало_истории = сам.каталог / "инициализирован"
            безопасный_путь(начало_истории)
            if сам.путь.exists():
                требовать(начало_истории.exists() and разобрать(начало_истории.read_bytes()) == {"база": str(сам.общий)}, "Потерян либо повреждён маркер инициализации")
                конверт = разобрать(сам.путь.read_bytes())
                требовать(isinstance(конверт, dict) and set(конверт) == {"данные", "sha256"}, "Повреждённое состояние не сбрасывается")
                состояние = конверт["данные"]
                требовать(конверт["sha256"] == хэш(состояние), "Повреждён хэш состояния")
                проверить_состояние(состояние, сам.общий)
            else:
                требовать(not начало_истории.exists(), "Исчезнувший журнал требует восстановления; повторная инициализация запрещена")
                установить(начало_истории, байты({"база": str(сам.общий)}))
                состояние = {"схема": "fum.приём-направлений.1", "база": str(сам.общий), "резервы": {}, "попытки": {}, "писатели": {}, "этапы": {}, "занятые": [], "импорт": {}, "история": None, "приёмы": {}}
                установить(сам.путь, байты({"данные": состояние, "sha256": хэш(состояние)}))
            исходные = байты(состояние)
            сам._замок_удержан = True
            try:
                yield состояние
                проверить_состояние(состояние, сам.общий)
                if байты(состояние) != исходные or not сам.путь.exists():
                    установить(сам.путь, байты({"данные": состояние, "sha256": хэш(состояние)}))
            finally:
                сам._замок_удержан = False
                сам.профиль.append({"стадия": "замок и сохранение", "длительность_наносекунды": time.monotonic_ns() - начало})

    def снимок_веток(сам):
        return гит(сам.корень, "for-each-ref", "--format=%(refname) %(objectname)", "refs/heads/", "refs/remotes/")

    def известные_номера(сам, снимок):
        начало = time.monotonic_ns()
        вершины = sorted({строка.rsplit(" ", 1)[1] for строка in снимок.splitlines()})
        требовать(вершины, "Нет объявленных веток")
        история = гит(сам.корень, "log", "--format=COMMIT %H", "--raw", "-z", "--no-abbrev", "--root", "--no-ext-diff", "--no-textconv", "--no-renames", "--full-history", "-m", *вершины, "--", "Планирование/карточки-шагов", "Требования", "Сбои")
        части = iter(история.split("\0"))
        версии = {}
        коммит = None
        for часть in части:
            часть = часть.lstrip("\n")
            if not часть:
                continue
            if часть.startswith("COMMIT "):
                коммит = часть[7:]
                требовать(шестнадцатеричный(коммит, 40), "Неверный коммит истории")
                continue
            запись = re.fullmatch(r":([0-7]{6}) ([0-7]{6}) ([0-9a-f]{40}) ([0-9a-f]{40}) [ADMT]", часть)
            требовать(запись is not None and коммит is not None, "Нераспознанная запись истории Git")
            путь = next(части, None)
            требовать(путь is not None, "Потерян путь истории Git")
            if not путь.endswith(".md") or Path(путь).name == "README.md":
                continue
            for режим, объект, сторона in ((запись[1], запись[3], "до"), (запись[2], запись[4], "после")):
                if режим in {"100644", "100755"}:
                    версии.setdefault((путь, объект), {"путь": путь, "blob": объект, "коммит": коммит, "сторона": сторона})
        объекты = sorted({объект for путь, объект in версии})
        содержимое = {}
        if объекты:
            ответ = гит(сам.корень, "cat-file", "--batch", вход=("\n".join(объекты) + "\n").encode("ascii"), сырые=True)
            позиция = 0
            for объект in объекты:
                конец = ответ.find(b"\n", позиция)
                заголовок = ответ[позиция:конец].decode("ascii").split(" ")
                требовать(конец >= позиция and len(заголовок) == 3 and заголовок[:2] == [объект, "blob"] and заголовок[2].isdigit(), "Неверный ответ чтения blob")
                размер = int(заголовок[2])
                позиция = конец + 1
                требовать(ответ[позиция + размер:позиция + размер + 1] == b"\n", "Неполный ответ чтения blob")
                try:
                    содержимое[объект] = ответ[позиция:позиция + размер].decode("utf-8")
                except UnicodeError as ошибка:
                    raise ОшибкаПриёма("Карточка истории не является UTF-8") from ошибка
                позиция += размер + 1
            требовать(позиция == len(ответ), "Лишние байты ответа чтения blob")
        номера = set()
        свидетельства = []
        for (путь, объект), источник in sorted(версии.items()):
            найденные = идентичности_карточки(путь, содержимое[объект])
            номера.update(найденные)
            if найденные:
                свидетельства.append({**источник, "номера": sorted(найденные)})
        сам.профиль.append({"стадия": "номера достижимой истории", "длительность_наносекунды": time.monotonic_ns() - начало, "refs": снимок, "идентичности": свидетельства})
        return номера

    def занятые_номера(сам, состояние, снимок):
        отпечаток = хэш({"refs": снимок, "реализация": ХЭШ_ИСПОЛНЕНИЯ})
        if состояние["история"] != отпечаток:
            состояние["занятые"] = sorted(set(состояние["занятые"]) | сам.известные_номера(снимок))
            состояние["история"] = отпечаток
        return set(состояние["занятые"]) | {номер for запись in состояние["резервы"].values() for номер in запись["номера"].values()}

    def выделить(сам, событие, виды, основание):
        требовать(текст(событие) and текст(основание), "Нужны событие и происхождение")
        требовать(виды and len(set(виды)) == len(виды) and set(виды) <= {"FUM-STEP", "FUM-REQ", "FUM-СБОЙ"}, "Неизвестный либо повторный вид номера")
        with сам.изменить() as состояние:
            прежний = состояние["резервы"].get(событие)
            if прежний:
                требовать(set(прежний["номера"]) == set(виды) and прежний["основание"] == основание, "Повтор изменил происхождение или виды")
                return прежний["номера"]
            снимок = сам.снимок_веток()
            занятые = сам.занятые_номера(состояние, снимок)
            номера = {}
            for вид in виды:
                максимум = max([int(номер.rsplit("-", 1)[1]) for номер in занятые if номер.startswith(вид + "-")] or [0])
                требовать(максимум < 9999, "Исчерпан четырёхзначный диапазон")
                номера[вид] = f"{вид}-{максимум + 1:04d}"
            требовать(снимок == сам.снимок_веток(), "Ветки сдвинулись во время выделения; повторите чтение")
            состояние["занятые"] = sorted(занятые | set(номера.values()))
            состояние["резервы"][событие] = {"номера": номера, "основание": основание, "refs_sha256": хэш(снимок)}
            return номера

    def учесть_резервы(сам, номера, основание):
        требовать(текст(основание) and isinstance(номера, list) and номера, "Нужны ручные резервы с происхождением")
        требовать(all(isinstance(номер, str) and re.fullmatch(r"FUM-(?:STEP|REQ|СБОЙ)-[0-9]{4}", номер) for номер in номера), "Неверный импорт номеров")
        with сам.изменить() as состояние:
            прежние = состояние["импорт"].get(основание)
            требовать(прежние is None or прежние == sorted(set(номера)), "Изменён повторный импорт")
            состояние["импорт"][основание] = sorted(set(номера))
            состояние["занятые"] = sorted(set(состояние["занятые"]) | set(номера))

    def резервировать(сам, событие, номера, основание):
        требовать(текст(событие) and текст(основание) and isinstance(номера, dict) and номера, "Нужен явный резерв с происхождением")
        for вид, номер in номера.items():
            требовать(вид in {"FUM-STEP", "FUM-REQ", "FUM-СБОЙ"} and isinstance(номер, str) and re.fullmatch(re.escape(вид) + r"-[0-9]{4}", номер), "Неверный резерв")
        with сам.изменить() as состояние:
            прежний = состояние["резервы"].get(событие)
            if прежний:
                требовать(прежний["номера"] == номера and прежний["основание"] == основание, "Конфликт повторного резерва")
                return прежний["номера"]
            занятые = set(состояние["занятые"]) | {номер for запись in состояние["резервы"].values() for номер in запись["номера"].values()}
            требовать(not занятые.intersection(номера.values()), "Номер зарезервирован другим событием")
            снимок = сам.снимок_веток()
            требовать(not сам.занятые_номера(состояние, снимок).intersection(номера.values()), "Явный резерв уже использован в истории")
            требовать(снимок == сам.снимок_веток(), "Сдвиг веток во время резерва")
            состояние["резервы"][событие] = {"номера": номера, "основание": основание, "refs_sha256": хэш(снимок)}
            состояние["занятые"] = sorted(set(состояние["занятые"]) | set(номера.values()))
            return номера

    def _наблюдать_владельца(сам):
        безопасный_путь(сам.корень, каталог=True)
        требовать(Path(гит(сам.корень, "rev-parse", "--show-toplevel").strip()).resolve() == сам.корень, "Изменился физический checkout")
        ветка = гит(сам.корень, "symbolic-ref", "HEAD").strip()
        коммит = гит(сам.корень, "rev-parse", "HEAD").strip()
        требовать(ветка_писателя(ветка) and шестнадцатеричный(коммит, 40), "Писателю нужна собственная ветка codex/ и полный HEAD")
        деревья = гит(сам.корень, "worktree", "list", "--porcelain", "-z")
        требовать(деревья.split("\0").count("branch " + ветка) == 1, "Ветка открыта в нескольких деревьях")
        требовать(ветка == гит(сам.корень, "symbolic-ref", "HEAD").strip() and коммит == гит(сам.корень, "rev-parse", "HEAD").strip(), "Ветка или HEAD сдвинулись при наблюдении")
        return {"задача": сам.задача, "путь": str(сам.корень), "ref": ветка, "HEAD": коммит}

    def проверить_владельца_под_замком(сам, состояние, *, ожидаемая_ветка=None, ожидаемый_коммит=None, **совместимость):
        """Внутри изменить(); прежний keyword из 32cac61b сохраняет совместимость."""
        требовать(set(совместимость) <= {"ожидаемый_ref"}, "Неизвестный прежний параметр владельца")
        if "ожидаемый_ref" in совместимость:
            требовать(ожидаемая_ветка is None or ожидаемая_ветка == совместимость["ожидаемый_ref"], "Несогласованные параметры ожидаемой ветки")
            ожидаемая_ветка = совместимость["ожидаемый_ref"]
        требовать(сам._замок_удержан, "Проверка владельца требует удерживаемого замка")
        наблюдение = сам._наблюдать_владельца()
        требовать(состояние["писатели"].get(str(сам.корень)) == {"задача": сам.задача, "ref": наблюдение["ref"]}, "Другой либо незарегистрированный писатель")
        требовать(ожидаемая_ветка is None or наблюдение["ref"] == ожидаемая_ветка, "Изменился ref этапа")
        требовать(ожидаемый_коммит is None or наблюдение["HEAD"] == ожидаемый_коммит, "Изменился HEAD этапа")
        return наблюдение

    def занять(сам):
        with сам.изменить() as состояние:
            наблюдение = сам._наблюдать_владельца()
            ветка = наблюдение["ref"]
            for путь, запись in состояние["писатели"].items():
                if путь == str(сам.корень) or запись["ref"] == ветка:
                    требовать(запись == {"задача": сам.задача, "ref": ветка} and путь == str(сам.корень), "Другой писатель дерева или ref")
            состояние["писатели"][str(сам.корень)] = {"задача": сам.задача, "ref": ветка}
            return сам.проверить_владельца_под_замком(состояние, ожидаемая_ветка=ветка, ожидаемый_коммит=наблюдение["HEAD"])

    def _владеть_записью(сам, состояние, запись, *, точная_база=False):
        требовать(запись["задача"] == сам.задача and запись["корень"] == str(сам.корень), "Чужой владелец записи")
        return сам.проверить_владельца_под_замком(состояние, ожидаемая_ветка=запись["ref"], ожидаемый_коммит=запись["база"] if точная_база else None)

    def начать_попытку(сам, событие, аргументы, *, проверить_допуск=None):
        требовать(текст(событие) and isinstance(аргументы, dict) and аргументы, "Нужен точный внешний вызов")
        проверить_структуру_данных(аргументы)
        сам.занять()
        with сам.изменить() as состояние:
            владелец = сам.проверить_владельца_под_замком(состояние)
            прежняя = состояние["попытки"].get(событие)
            if прежняя:
                сам._владеть_записью(состояние, прежняя)
                требовать(прежняя["аргументы_sha256"] == хэш(аргументы), "Внешний повтор изменил аргументы")
                return {**прежняя, "разрешён_вызов": False}
            if проверить_допуск is not None:
                проверить_допуск(состояние)
                владелец = сам.проверить_владельца_под_замком(состояние, ожидаемая_ветка=владелец["ref"], ожидаемый_коммит=владелец["HEAD"])
            запись = {"попытка": str(uuid.uuid4()), "аргументы": аргументы, "аргументы_sha256": хэш(аргументы), "состояние": "исход неизвестен", "ответ": None, "задача": сам.задача, "корень": str(сам.корень), "ref": владелец["ref"], "база": владелец["HEAD"]}
            состояние["попытки"][событие] = запись
            return {**запись, "разрешён_вызов": True}

    def сохранить_ответ(сам, событие, попытка, ответ):
        требовать(isinstance(ответ, dict), "Нужен полный ответ runtime")
        проверить_структуру_данных(ответ)
        with сам.изменить() as состояние:
            запись = состояние["попытки"].get(событие)
            требовать(запись and запись["попытка"] == попытка, "Неизвестная попытка")
            сам._владеть_записью(состояние, запись)
            if запись["ответ"] is not None:
                требовать(байты(запись["ответ"]) == байты(ответ), "Повтор receipt изменил ответ")
                return запись
            запись["ответ"] = ответ
            запись["состояние"] = состояние_ответа(ответ)
            return запись

    def применить_файлы(сам, событие, этап, файлы, *, ожидаемые_байты=None, ожидаемая_ветка=None, ожидаемая_база=None, проверить_окружение=None, проверить_допуск=None):
        """Долговечный план установки. Перезапуск допускает только before/after."""
        требовать(текст(событие) and текст(этап) and isinstance(файлы, dict) and файлы, "Нужен конечный план файлов")
        требовать(проверить_окружение is None or callable(проверить_окружение), "Нужна вызываемая проверка окружения")
        требовать(проверить_допуск is None or callable(проверить_допуск), "Нужна вызываемая проверка допуска")
        требовать(ожидаемые_байты is None or type(ожидаемые_байты) is dict and set(ожидаемые_байты) == set(файлы) and all(значение is None or type(значение) is str for значение in ожидаемые_байты.values()), "Неверный снимок исходных байтов")
        for имя, содержимое in файлы.items():
            путь = путь_результата(имя)
            требовать(isinstance(содержимое, str), "Нужны точные UTF-8 байты результата")
            байты(содержимое)
            безопасный_путь(сам.корень / путь)
        сам.занять()
        ключ = ключ_этапа(событие, этап)
        with сам.изменить() as состояние:
            владелец = сам.проверить_владельца_под_замком(состояние)
            if проверить_допуск is not None:
                проверить_допуск(состояние)
            запись = состояние["этапы"].get(ключ)
            if запись is None:
                сам.проверить_владельца_под_замком(состояние, ожидаемая_ветка=ожидаемая_ветка, ожидаемый_коммит=ожидаемая_база)
                запись = {"событие": событие, "этап": этап, "задача": сам.задача, "корень": str(сам.корень), "ref": владелец["ref"], "база": владелец["HEAD"], "файлы": {}, "готов": False, "коммит": None}
                for имя, содержимое in файлы.items():
                    путь = сам.корень / имя
                    запись["файлы"][имя] = {"до": путь.read_bytes().decode("utf-8") if путь.exists() else None, "после": содержимое}
                состояние["этапы"][ключ] = запись
            требовать(ожидаемые_байты is None or {имя: изменение["до"] for имя, изменение in запись["файлы"].items()} == ожидаемые_байты, "Исходные байты изменились после подготовки плана")
            требовать(ожидаемая_ветка is None or запись["ref"] == ожидаемая_ветка, "Подменена ветка плана")
            требовать(ожидаемая_база is None or запись["база"] == ожидаемая_база, "Подменена база плана")
            сам._владеть_записью(состояние, запись, точная_база=not запись["готов"])
            требовать({имя: значение["после"] for имя, значение in запись["файлы"].items()} == файлы, "Повтор изменил план этапа")
        # Намерение уже синхронизировано до первой записи checkout.
        with сам.изменить() as состояние:
            запись = состояние["этапы"][ключ]
            владелец = сам._владеть_записью(состояние, запись, точная_база=not запись["готов"])
            if проверить_допуск is not None:
                проверить_допуск(состояние)
            if проверить_окружение is not None:
                проверить_окружение()
            for имя, значение in запись["файлы"].items():
                путь = сам.корень / имя
                безопасный_путь(путь)
                текущее = путь.read_bytes().decode("utf-8") if путь.exists() else None
                допустимые = (значение["после"],) if запись["готов"] else (значение["до"], значение["после"])
                требовать(текущее in допустимые, "Файл изменён вне сохранённого плана: " + имя)
            for имя, значение in запись["файлы"].items():
                путь = сам.корень / имя
                # Совпавшие after-байты могли остаться после replace без fsync.
                создать_каталоги(путь.parent, сам.корень)
                if not путь.exists() or путь.read_bytes() != значение["после"].encode("utf-8"):
                    установить(путь, значение["после"].encode())
            сам.проверить_владельца_под_замком(состояние, ожидаемая_ветка=владелец["ref"], ожидаемый_коммит=владелец["HEAD"])
            запись["готов"] = True
            return {имя: hashlib.sha256(значение["после"].encode()).hexdigest() for имя, значение in запись["файлы"].items()}

    def подтвердить_коммит(сам, событие, этап, коммит):
        требовать(isinstance(коммит, str) and re.fullmatch(r"[0-9a-f]{40}", коммит), "Нужен полный OID коммита")
        with сам.изменить() as состояние:
            запись = состояние["этапы"].get(ключ_этапа(событие, этап))
            требовать(запись and запись["готов"], "Нет завершённой локальной стадии")
            владелец = сам._владеть_записью(состояние, запись)
            требовать(запись["коммит"] is None or запись["коммит"] == коммит, "Квитанция коммита уже закреплена")
            требовать(гит(сам.корень, "cat-file", "-t", коммит).strip() == "commit", "OID не является коммитом")
            гит(сам.корень, "merge-base", "--is-ancestor", запись["база"], коммит)
            гит(сам.корень, "merge-base", "--is-ancestor", коммит, владелец["HEAD"])
            for имя, значение in запись["файлы"].items():
                элементы = гит(сам.корень, "ls-tree", "-z", коммит, "--", ":(literal)" + имя).split("\0")
                требовать(len(элементы) == 2 and элементы[1] == "" and "\t" in элементы[0], "В коммите нет единственной записи результата")
                свойства, путь = элементы[0].split("\t", 1)
                части = свойства.split(" ")
                требовать(len(части) == 3 and части[0] in {"100644", "100755"} and части[1] == "blob" and путь == имя, "Результат коммита не является обычным файлом")

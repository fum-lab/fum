"""Явный принятый срез, заинтересованные получатели и детерминированные поручения."""
import hashlib
from pathlib import Path
import re
import time

from приём_направления import поля, требовать, разобрать, хэш, идентификатор_задачи, текст
from доставка_гит import физический_корень, полный_объект, гит, объект_файла, предок, снимок


def принять_источник(описание):
    поля(описание, {"корень", "ref", "коммит", "владелец", "срез", "приёмка"})
    корень = физический_корень(описание["корень"])
    for ключ in ("коммит", "срез"):
        полный_объект(корень, описание[ключ])
    требовать(описание["ref"].startswith("refs/heads/") and идентификатор_задачи(описание["владелец"]), "Нет точного источника и владельца")
    гит(корень, "check-ref-format", описание["ref"])
    требовать(гит(корень, "show-ref", "--verify", "--hash", описание["ref"]) == описание["коммит"], "Сдвинулся источник")
    поля(описание["приёмка"], {"путь", "sha256"})
    исходные = объект_файла(корень, описание["коммит"], описание["приёмка"]["путь"])
    требовать(hashlib.sha256(исходные).hexdigest() == описание["приёмка"]["sha256"], "Подменена приёмка")
    решение = разобрать(исходные)
    поля(решение, {"схема", "коммит", "дерево", "проверяющий", "состояние", "граница", "свидетельства"})
    требовать(решение["схема"] == "fum.решение-приёмки-среза.1" and решение["состояние"] == "принят промежуточный срез", "Источник не является явно принятым промежуточным срезом")
    требовать(решение["коммит"] == описание["срез"] and решение["дерево"] == гит(корень, "rev-parse", описание["срез"] + "^{tree}"), "Приёмка другого среза")
    требовать(предок(корень, описание["срез"], описание["коммит"]), "Свидетельство не связано с историей среза")
    требовать(идентификатор_задачи(решение["проверяющий"]) and текст(решение["граница"]), "Нет проверяющего или границы приёмки")
    требовать(type(решение["свидетельства"]) is list and решение["свидетельства"], "Нужны сохранённые свидетельства приёмки")
    for свидетельство in решение["свидетельства"]:
        поля(свидетельство, {"путь", "sha256"})
        данные = объект_файла(корень, описание["коммит"], свидетельство["путь"])
        требовать(hashlib.sha256(данные).hexdigest() == свидетельство["sha256"], "Повреждено свидетельство приёмки")
    return {**описание, "дерево": решение["дерево"], "решение": решение, "полная_приёмка": False,
            "версия": хэш({"срез": описание["срез"], "решение": решение})}


def отношение(корень, источник, цель):
    полный_объект(корень, источник)
    if предок(корень, источник, цель):
        return "в предках", []
    if гит(корень, "rev-parse", источник + "^{tree}") == гит(корень, "rev-parse", цель + "^{tree}"):
        return "равное дерево", []
    патчи = гит(корень, "cherry", цель, источник).splitlines()
    слияния = гит(корень, "rev-list", "--merges", цель + ".." + источник)
    if any(строка.startswith("-") for строка in патчи):
        return ("эквивалентные патчи" if all(строка.startswith("-") for строка in патчи) and not слияния else "выборочный перенос"), патчи
    return "недоставленные коммиты", патчи


def построить_план(описание, получатели, владельцы, *, профиль=None):
    начало = time.monotonic_ns()
    источник = принять_источник(описание)
    требовать(type(владельцы) is dict and type(получатели) is list and получатели, "Нужны явные получатели и реестр владельцев")
    ветки = []
    for корень, владелец in владельцы.items():
        поля(владелец, {"задача", "ref"})
        требовать(идентификатор_задачи(владелец["задача"]), "Неверный UUID")
        ветки.append(владелец["ref"])
    требовать(len(ветки) == len(set(ветки)), "Одна ветка назначена нескольким владельцам")
    записи = []
    for вход in получатели:
        # Строка означает явный интерес координатора без вывода зависимости из истории.
        выбор = {"корень": вход, "причина": "Явный список координатора", "зависимость": "unknown"} if isinstance(вход, str) else вход
        поля(выбор, {"корень", "причина", "зависимость"})
        требовать(текст(выбор["причина"]) and текст(выбор["зависимость"]), "Нужна причина выбора и граница зависимости")
        корень = выбор["корень"]
        требовать(корень in владельцы, "Получатель не назначен владельцу")
        владелец = владельцы[корень]
        запись = снимок(корень, владелец["задача"], владелец["ref"])
        вид, патчи = отношение(корень, источник["срез"], запись["коммит"])
        запись.update(отношение=вид, патчи=патчи, причина=выбор["причина"], зависимость=выбор["зависимость"],
                      сигнал_недоставки=вид not in ("в предках", "равное дерево"), подтверждение="unknown")
        записи.append(запись)
    требовать(len({запись["корень"] for запись in записи}) == len(записи), "Повтор получателя")
    for запись in записи:
        повтор = снимок(запись["корень"], запись["владелец"], запись["ref"])
        требовать(all(повтор[ключ] == запись[ключ] for ключ in повтор), "Получатель сдвинулся во время планирования")
    требовать(гит(источник["корень"], "show-ref", "--verify", "--hash", источник["ref"]) == источник["коммит"], "Источник сдвинулся во время планирования")
    конец_наблюдения = time.monotonic_ns()
    записи.sort(key=lambda запись: (запись["ref"], запись["владелец"], запись["корень"]))
    план = {"схема": "fum.план-обратной-доставки.1", "источник": источник, "владельцы_sha256": хэш(владельцы), "получатели": записи}
    план["идентификатор"] = хэш(план)
    if профиль is not None:
        профиль.extend([{"стадия": "наблюдение", "длительность_наносекунды": конец_наблюдения - начало},
                        {"стадия": "план", "длительность_наносекунды": time.monotonic_ns() - конец_наблюдения}])
    return план


def проверить_план(план):
    поля(план, {"схема", "источник", "владельцы_sha256", "получатели", "идентификатор"})
    требовать(план["схема"] == "fum.план-обратной-доставки.1" and план["идентификатор"] == хэш({ключ: значение for ключ, значение in план.items() if ключ != "идентификатор"}), "Повреждён план")
    источник = план["источник"]
    поля(источник, {"корень", "ref", "коммит", "владелец", "срез", "приёмка", "дерево", "решение", "полная_приёмка", "версия"})
    требовать(источник["полная_приёмка"] is False and источник["версия"] == хэш({"срез": источник["срез"], "решение": источник["решение"]}), "Неизвестная граница приёмки")
    требовать(type(план["получатели"]) is list and план["получатели"], "Пустой адресный план")
    порядок = []
    for запись in план["получатели"]:
        поля(запись, {"корень", "владелец", "ref", "коммит", "дерево", "отношение", "патчи", "причина", "зависимость", "сигнал_недоставки", "подтверждение"})
        требовать(идентификатор_задачи(запись["владелец"]) and isinstance(запись["корень"], str) and Path(запись["корень"]).is_absolute(), "Неверный получатель")
        требовать(isinstance(запись["ref"], str) and запись["ref"].startswith("refs/heads/codex/"), "Неверный ref получателя")
        for ключ in ("коммит", "дерево"):
            требовать(isinstance(запись[ключ], str) and re.fullmatch(r"(?:[0-9a-f]{40}|[0-9a-f]{64})", запись[ключ]), "Неверный OID плана")
        требовать(запись["отношение"] in ("в предках", "равное дерево", "эквивалентные патчи", "выборочный перенос", "недоставленные коммиты"), "Неизвестное отношение")
        требовать(type(запись["патчи"]) is list and all(isinstance(патч, str) and re.fullmatch(r"[+-] (?:[0-9a-f]{40}|[0-9a-f]{64})", патч) for патч in запись["патчи"]), "Неверные наблюдения патчей")
        требовать(текст(запись["причина"]) and текст(запись["зависимость"]) and запись["подтверждение"] == "unknown", "Неверная граница поручения")
        требовать(type(запись["сигнал_недоставки"]) is bool and запись["сигнал_недоставки"] == (запись["отношение"] not in ("в предках", "равное дерево")), "Неверный сигнал")
        порядок.append((запись["ref"], запись["владелец"], запись["корень"]))
    требовать(порядок == sorted(set(порядок)) and len({строка[0] for строка in порядок}) == len(порядок)
              and len({строка[2] for строка in порядок}) == len(порядок), "Повтор или неверный порядок получателей")
    return план



    def test_точный_предел_и_закрытые_каналы_живого_процесса(проверка):
        результат=проверка.запустить("import os; os.write(1,b'x'*1000)",предел_байтов=1000)
        проверка.assertTrue(результат['полнота'])
        проверка.каталог=проверка.корень/'второй'

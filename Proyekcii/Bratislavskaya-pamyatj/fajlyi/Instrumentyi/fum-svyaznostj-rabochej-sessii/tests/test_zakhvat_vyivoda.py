    def test_оборванная_выдача_не_дополняется_второй_диагностикой(проверка):
        проверка.запустить("print('готово')")
        путь=Path(__file__).resolve().parents[1]/'scripts'/'захватить-вывод.py'
        описание=importlib.util.spec_from_file_location('фикстура_кли',путь)
        модуль=importlib.util.module_from_spec(описание)
        описание.loader.exec_module(модуль)
        with patch.object(модуль,'записать',side_effect=BrokenPipeError()) as подмена:
            код=модуль.выполнить(['--каталог',str(проверка.каталог),'представить','--sha256',проверка.хэш_манифеста()])
        проверка.assertEqual(код,2)
        проверка.assertEqual(подмена.call_count,1)


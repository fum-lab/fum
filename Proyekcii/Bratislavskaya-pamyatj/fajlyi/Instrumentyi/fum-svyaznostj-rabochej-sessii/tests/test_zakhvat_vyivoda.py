    def test_отказ_устойчивой_записи_не_создаёт_конечную_квитанцию(проверка):
        with patch('захват_вывода.os.fsync',side_effect=OSError('фикстура диска')):
            with проверка.assertRaises(OSError): проверка.запустить("print('не запускать')")
        проверка.assertFalse((проверка.каталог/'манифест.json').exists())

    def test_короткая_запись_продолжается_и_нулевая_отказывает(проверка):
        from захват_вывода import записать
        with patch('захват_вывода.os.write',side_effect=[2,1]) as подмена:
            записать(99,b'abc')
            проверка.assertEqual(подмена.call_count,2)
        with patch('захват_вывода.os.write',return_value=0):
            with проверка.assertRaises(OSError): записать(99,b'abc')

    def test_наблюдения_адресуют_свои_каналы(проверка):
        результат=проверка.запустить("import os; os.write(1,b'a'*100); os.write(2,b'b'*100)")
        записи=[json.loads(строка) for строка in (проверка.каталог/'наблюдения.jsonl').read_bytes().splitlines()]
        проверка.assertEqual([з['номер_наблюдения'] for з in записи],list(range(1,len(записи)+1)))
        for запись in записи:
            данные=(проверка.каталог/(запись['канал']+'.bin')).read_bytes()
            часть=данные[запись['смещение']:запись['смещение']+запись['сохранено_байтов']]
            проверка.assertEqual(hashlib.sha256(часть).hexdigest(),запись['sha256'])
        проверка.assertEqual(результат['наблюдения']['пропущено'],0)

    def test_кли_не_интерпретирует_оболочку_и_ограничивает_весь_вывод(проверка):
        путь=Path(__file__).resolve().parents[1]/'scripts'/'захватить-вывод.py'
        команда=[sys.executable,str(путь),'--каталог',str(проверка.каталог),'--бюджет','16000',
            'запустить','--корень',str(проверка.корень),'--задача',проверка.задача,'--',
            sys.executable,'-c','import sys; print(sys.argv[1])','$(не-команда);*']
        результат=subprocess.run(команда,capture_output=True,timeout=5)
        проверка.assertEqual(результат.returncode,0,результат.stderr)
        проверка.assertEqual(результат.stderr,b'')
        проверка.assertLessEqual(len(результат.stdout)+len(результат.stderr),16000)
        проверка.assertEqual((проверка.каталог/'stdout.bin').read_text(),'$(не-команда);*\n')


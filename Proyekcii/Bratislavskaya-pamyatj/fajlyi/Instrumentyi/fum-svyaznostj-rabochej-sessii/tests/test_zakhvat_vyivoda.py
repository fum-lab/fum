    def test_хэш_производителя_не_заменяется_повторным_чтением_кли(проверка):
        import захват_вывода
        путь=Path(__file__).resolve().parents[1]/'scripts'/'захватить-вывод.py'
        описание=importlib.util.spec_from_file_location('фикстура_кли',путь)
        модуль=importlib.util.module_from_spec(описание);описание.loader.exec_module(модуль)
        производитель=захват_вывода.захватить_с_хэшем
        def подменить(*аргументы,**параметры):
            результат,ожидаемый=производитель(*аргументы,**параметры)
            проверка.assertEqual(ожидаемый,проверка.хэш_манифеста())
            изменённый = dict(результат, задача='00000000-0000-0000-0000-000000000188')
            (проверка.каталог/'манифест.json').write_bytes(закодировать(изменённый))
            return результат,ожидаемый
        with patch.object(модуль,'захватить_с_хэшем',side_effect=подменить), patch.object(модуль,'записать') as выдача:
            код=модуль.выполнить(['--каталог',str(проверка.каталог),'запустить','--корень',str(проверка.корень),
                '--задача',проверка.задача,'--',sys.executable,'-c','pass'])
        проверка.assertEqual(код,2)
        проверка.assertLessEqual(len(выдача.call_args.args[1]),16000)

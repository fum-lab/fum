    def test_специальный_файл_не_открывается_как_канал(проверка):
        проверка.запустить("print('готово')")
        путь=проверка.каталог/'stdout.bin'
        путь.unlink();os.mkfifo(путь)
        ожидаемый=проверка.хэш_манифеста()
        # Подмена open даёт тесту конечный отказ даже на старом блокирующем читателе.

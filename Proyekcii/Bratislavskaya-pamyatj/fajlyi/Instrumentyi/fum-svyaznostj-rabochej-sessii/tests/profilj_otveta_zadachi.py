"""Парный профиль сохранённой полной выдачи и компактного ответа."""
import argparse
import hashlib
import json
import statistics
import sys
import time
import tracemalloc
from pathlib import Path

from test_компактный_ответ_задачи import снимок_ответа, оболочка, ЗАДАЧА
from компактный_ответ_задачи import представить_ответ, разобрать
from компактный_остаток import закодировать


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    параметры = разбор.parse_args()
    значение = снимок_ответа()
    значение["turns"][0]["items"][1]["output"] = "Открытая командная нагрузка.\n" * 100000
    данные = закодировать(оболочка(значение)); хэш = hashlib.sha256(данные).hexdigest()

    def полный():
        assert hashlib.sha256(данные).hexdigest() == хэш
        return закодировать(разобрать(данные))

    def компактный():
        return закодировать(представить_ответ(данные, хэш, ЗАДАЧА))

    функции = {"полная_выдача": полный, "компактная_выдача": компактный}
    времена = {имя: [] for имя in функции}; выходы = {}
    for повтор in range(7):
        for имя in (tuple(функции) if повтор % 2 == 0 else tuple(reversed(функции))):
            начало = time.perf_counter_ns(); выходы[имя] = функции[имя]()
            времена[имя].append(time.perf_counter_ns() - начало)
    память = {}
    for имя, функция in функции.items():
        tracemalloc.start(); функция(); память[имя] = tracemalloc.get_traced_memory()[1]; tracemalloc.stop()
    assert выходы["полная_выдача"] == данные
    срез = json.loads(выходы["компактная_выдача"])
    assert срез["ответ"]["оригинал"] == значение["turns"][0]["items"][2]
    assert срез["элементов_всего"] == 6 and срез["элементов_опущено"] == 5
    каталог = Path(__file__).resolve().parents[1]
    результат = {"схема": "fum.профиль-ответа-задачи.1", "Python": sys.version.split()[0],
        "вход_байты": len(данные), "вход_sha256": хэш, "повторы": 7,
        "наносекунды": времена, "медианы_наносекунды": {имя: statistics.median(ряд) for имя, ряд in времена.items()},
        "пиковые_байты_Python": память, "выходные_байты": {имя: len(выход) for имя, выход in выходы.items()},
        "исходники_sha256": {имя: hashlib.sha256((каталог / имя).read_bytes()).hexdigest() for имя in
            ("scripts/компактный_ответ_задачи.py", "scripts/компактный_остаток.py", "tests/профиль_ответа_задачи.py", "tests/test_компактный_ответ_задачи.py")},
        "смысловая_сверка": True,
        "граница": "Один синтетический снимок. SHA, разбор и сериализация включены; подготовка, диск, API, сборка и генерация исключены. Полная выдача разбирает только оболочку, компактная дополнительно разбирает вложенный JSON. Пик Python измерен отдельно; это не RSS, токены или общий расход задачи."}
    параметры.выход.write_bytes(закодировать(результат))
    print(json.dumps({ключ: результат[ключ] for ключ in ("вход_байты", "выходные_байты", "медианы_наносекунды", "пиковые_байты_Python", "смысловая_сверка")}, ensure_ascii=False))


if __name__ == "__main__":
    выполнить()

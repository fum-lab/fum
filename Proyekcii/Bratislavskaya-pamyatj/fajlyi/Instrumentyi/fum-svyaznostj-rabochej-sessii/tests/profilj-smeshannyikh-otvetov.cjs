const именаСчётчиков = ["симулированный_api", "запись_файла", "команда", "загрузка_кэша", "запись_кэша"];
const нули = () => Object.fromEntries(именаСчётчиков.map(имя => [имя, 0]));
const хэш = данные => крипто.createHash("sha256").update(данные).digest("hex");
const миллисекунды = начало => Number(process.hrtime.bigint() - начало) / 1000000;
const медиана = ряд => {const числа = [...ряд].sort((а, б) => а - б); return числа.length % 2 ? числа[Math.floor(числа.length / 2)] : (числа[числа.length / 2 - 1] + числа[числа.length / 2]) / 2;};

function свести(шаги, файлы) {
    утверждать.ok(Array.isArray(шаги) && шаги.length > 0 && Array.isArray(файлы));
    const итог = {шаги: шаги.length, байты_модельной_выдачи: 0, байты_полных_выдач: 0,
        байты_уникальных_файлов: 0, время_мс: 0, вызовы: нули(), живые_api: 0};
    for (const шаг of шаги) {
        утверждать.ok(["новый", "сохранённый"].includes(шаг.режим));
        утверждать.ok(["малый", "крупный"].includes(шаг.размер));
        for (const имя of ["полезные_байты", "полные_байты"]) утверждать.ok(Number.isSafeInteger(шаг[имя]) && шаг[имя] > 0);
        утверждать.ok(Number.isFinite(шаг.длительность_мс) && шаг.длительность_мс >= 0);
        итог.байты_модельной_выдачи += шаг.полезные_байты;
        итог.байты_полных_выдач += шаг.полные_байты;
        итог.время_мс += шаг.длительность_мс;
        for (const имя of именаСчётчиков) {
            утверждать.ok(Number.isSafeInteger(шаг.вызовы[имя]) && шаг.вызовы[имя] >= 0);
            итог.вызовы[имя] += шаг.вызовы[имя];
        }
    }
    for (const файл of файлы) {
        утверждать.ok(Number.isSafeInteger(файл.байты) && файл.байты > 0);
        итог.байты_уникальных_файлов += файл.байты;
    }
    утверждать.equal(итог.вызовы.запись_файла, файлы.length);
    итог.снижение_байтов_проценты = 100 * (1 - итог.байты_модельной_выдачи / итог.байты_полных_выдач);
    return итог;
}

function ответ(крупный) {
    const вход = {schemaVersion: 1, thread: {id: задача, kind: "codex", status: {type: "active"}},
        page: {order: "newest_first", limit: 1, nextCursor: null, hasMore: false},
        turns: [{id: "ход", status: "inProgress", error: null, startedAt: 100, completedAt: null, durationMs: null,
            items: [{type: "commandExecution", command: "НЕ ВЫПОЛНЯТЬ", output: крупный ? "я".repeat(2000000) : ""},
                {type: "agentMessage", id: "ответ", text: "Последний ответ: ёж 🦔\n", phase: "commentary"}]}]};
    return {content: [{type: "text", text: JSON.stringify(вход)}], isError: false};
}

async function прогнать(повторы = 7, профиль = "прежний") {
    утверждать.ok(Number.isInteger(повторы) && повторы > 0 && повторы <= 20);
    утверждать.ok(["прежний", "порождённый"].includes(профиль));
    const ответы = {малый: ответ(false), крупный: ответ(true)};
    const оригиналы = Object.fromEntries(Object.entries(ответы).map(([имя, объект]) => [имя, Buffer.from(JSON.stringify(объект) + "\n")]));
    const временный = фс.realpathSync(фс.mkdtempSync(пути.join(ос.tmpdir(), "fum-mixed-")));
    const циклы = [];
    try {
        for (let цикл = 0; цикл < повторы; цикл++) {
            const кэш = new Map(); const принятые = new Map(); const файлы = []; const шаги = [];
            let текущий; let счётчики; let времена;
            function учесть(имя, действие) {
                const начало = process.hrtime.bigint(); счётчики[имя]++;
                try {return действие();} finally {времена[имя] += миллисекунды(начало);}
            }
            const среда = {
                загрузить: ключ => учесть("загрузка_кэша", () => кэш.get(ключ)),
                сохранить: (ключ, значение) => учесть("запись_кэша", () => кэш.set(ключ, значение)),
                инструменты: {
                    mcp__codex_app__read_thread: async параметры => учесть("симулированный_api", () => {
                        утверждать.deepEqual(параметры, {threadId: задача, turnLimit: 1, includeOutputs: false, maxOutputCharsPerItem: 1500});
                        return ответы[текущий];
                    }),
                    exec_command: async параметры => учесть("команда", () => {
                        утверждать.equal(параметры.workdir, корень);
                        try {return {exit_code: 0, output: процессы.execFileSync("sh", ["-c", параметры.cmd],
                            {cwd: корень, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"]})};}
                        catch (ошибка) {return {exit_code: ошибка.status ?? 1, output: "Отказ локальной команды профиля"};}
                    }),
                    apply_patch: async патч => учесть("запись_файла", () => {
                        const строки = патч.split("\n");
                        утверждать.equal(строки[0], "*** Begin Patch");
                        утверждать.ok(строки[1].startsWith("*** Add File: "));
                        утверждать.equal(строки.at(-2), "*** End Patch");
                        const путь = строки[1].slice("*** Add File: ".length);
                        утверждать.equal(пути.dirname(путь), временный);
                        const данные = Buffer.from(строки.slice(2, -2).map(строка => {утверждать.ok(строка.startsWith("+")); return строка.slice(1);}).join("\n") + "\n");
                        утверждать.deepEqual(данные, оригиналы[текущий]);
                        фс.writeFileSync(путь, данные, {flag: "wx", mode: 0o600});
                        файлы.push({размер: текущий, байты: данные.length, sha256: хэш(данные)});
                        return {isError: false};
                    })
                }
            };
            const порядок = цикл % 2 ? ["крупный", "малый"] : ["малый", "крупный"];
            for (let круг = 0; круг < 3; круг++) for (const размер of порядок) {
                текущий = размер; счётчики = нули(); времена = нули();
                const режим = круг === 0 ? "новый" : "сохранённый";
                const снимок = пути.join(временный, String(цикл) + "-" + размер + ".json");
                const начало = process.hrtime.bigint();
                const результат = await прочитать_кратко(среда, {корень, задача, режим, снимок, ключ_кэша: размер, максимум_байтов: 16000,
                    профиль_представления: профиль});
                const длительность = миллисекунды(начало);
                утверждать.equal(результат.схема, "fum.срез-ответа-задачи.1");
                утверждать.equal(результат.завершение_задачи_доказано, false);
                утверждать.equal(результат.живой_источник_перепроверен, false);
                утверждать.equal(результат.полный_снимок.sha256, хэш(оригиналы[размер]));
                утверждать.deepEqual(фс.readFileSync(снимок), оригиналы[размер]);
                if (режим === "новый") принятые.set(размер, результат);
                else утверждать.deepEqual(результат, принятые.get(размер));
                шаги.push({номер: шаги.length + 1, размер, режим, полезные_байты: Buffer.byteLength(JSON.stringify(результат) + "\n"),
                    хэш_семантики: хэш(JSON.stringify({...результат,
                        полный_снимок: {...результат.полный_снимок, путь: "<путь-снимка>"}})),
                    полные_байты: оригиналы[размер].length, длительность_мс: длительность, вызовы: счётчики, вложенное_время_мс: времена});
            }
            const итог = свести(шаги, файлы);
            утверждать.deepEqual(итог.вызовы, {симулированный_api: 2, запись_файла: 2, команда: 10, загрузка_кэша: 4, запись_кэша: 8});
            циклы.push({номер: цикл + 1, шаги, файлы, итог});
        }
        const шаги = циклы.flatMap(цикл => цикл.шаги), группы = {};
        for (const размер of ["малый", "крупный"]) for (const режим of ["новый", "сохранённый"]) {
            const выборка = шаги.filter(шаг => шаг.размер === размер && шаг.режим === режим);
            группы[размер + "_" + режим] = {число: выборка.length, медиана_мс: медиана(выборка.map(шаг => шаг.длительность_мс)),
                полные_байты: выборка[0].полные_байты, полезные_байты_мин: Math.min(...выборка.map(шаг => шаг.полезные_байты)),
                полезные_байты_макс: Math.max(...выборка.map(шаг => шаг.полезные_байты))};
        }
        const исходники = ["Инструменты/fum-svyaznostj-rabochej-sessii/scripts/адаптер_ответа.cjs",
            "Инструменты/fum-svyaznostj-rabochej-sessii/scripts/показать-ответ-задачи.py",
            "Инструменты/fum-svyaznostj-rabochej-sessii/scripts/компактный_ответ_задачи.py",
            "Инструменты/fum-svyaznostj-rabochej-sessii/scripts/компактный_остаток.py",
            "Проекты/рабочий-контекст/общие/Python/поддержка_моделей.py",
            "Проекты/рабочий-контекст/порождённые/модели_ответа.py",
            "Проекты/рабочий-контекст/контракты/описание-ответа.json",
            "Инструменты/fum-svyaznostj-rabochej-sessii/tests/профиль-смешанных-ответов.cjs"];
        return {схема: "fum.смешанный-профиль-ответов.1", профиль_представления: профиль, повторы, циклы, группы,
            итог: свести(шаги, циклы.flatMap(цикл => цикл.файлы)),
            медиана_цикла_мс: медиана(циклы.map(цикл => цикл.итог.время_мс)),
            исходники: Object.fromEntries(исходники.map(имя => [имя, хэш(фс.readFileSync(пути.join(корень, имя)))])),
            граница: "Настоящие адаптер, Python CLI, shell и файловая запись; read_thread заменён открытой фикстурой. Подготовка и контроль после вызова исключены из времени шага. Вложенные интервалы входят в шаг и повторно не суммируются.",
            ограничения: ["Состав последовательности задан, частота реальной эксплуатации не наблюдалась", "Живой API, сеть, токены и RSS не измерены",
                "Байты полезной выдачи включают фактический приватный путь, но путь не опубликован", "Байты полных выдач — условное повторение полного JSON при каждом чтении, без служебной оболочки инструмента",
                "Повторное чтение доказывает соответствие сохранённому SHA, не свежесть живого состояния",
                "Измеряется явно выбранный профиль CLI: " + профиль, "Полезные байты вычислены повторной JS-сериализацией результата с LF",
                "SHA семантики вычисляется после измерения; только приватный путь снимка заменён фиксированным маркером"]};
    } finally {фс.rmSync(временный, {recursive: true, force: true});}
}


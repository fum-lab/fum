"""Детектор выбирает компактное чтение по фактическим байтам."""
import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from test_компактный_остаток import снимок, байты

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from детектор_вывода import потребить


class ПроверкаДетектораВывода(unittest.TestCase):
    def вызвать(проверка, данные=None, **параметры):
        данные = байты(снимок()) if данные is None else данные
        return потребить(данные, hashlib.sha256(данные).hexdigest(), 16000, 3, **параметры)

    def test_превышение_само_выбирает_существующую_страницу(проверка):
        данные = байты(снимок())
        вывод, квитанция = проверка.вызвать(данные, начало=0, число=1)
        страница = json.loads(вывод)
        проверка.assertEqual(квитанция['реакция'], 'компактный-остаток')
        проверка.assertEqual(квитанция['единица'], 'байты')
        проверка.assertTrue(квитанция['превышен_бюджет'])
        проверка.assertEqual(квитанция['источник']['sha256'], hashlib.sha256(данные).hexdigest())
        проверка.assertEqual(квитанция['источник']['байты'], len(данные))
        проверка.assertEqual(страница['сообщения'][0]['оригинал']['содержимое'], снимок()['сообщения'][0]['содержимое'])
        проверка.assertEqual(страница['непоказанных_необработанных'], 2)
        проверка.assertFalse(страница['завершение_задачи_доказано'])
        проверка.assertLessEqual(len(вывод), 16000)
        проверка.assertEqual(квитанция['выход']['байты'], len(вывод))

    def test_порог_равенства_и_один_байт_сверх(проверка):
        данные = байты(снимок())
        полный, квитанция = потребить(данные, hashlib.sha256(данные).hexdigest(), len(данные), 3)
        проверка.assertEqual(полный, данные)
        проверка.assertFalse(квитанция['превышен_бюджет'])
        компактный, квитанция = потребить(данные, hashlib.sha256(данные).hexdigest(), len(данные)-1, 3)
        проверка.assertTrue(квитанция['превышен_бюджет'])
        проверка.assertNotEqual(компактный, данные)

    def test_ошибочный_производитель_хэш_и_бюджет_не_становятся_успехом(проверка):
        данные = байты(снимок()); хэш = hashlib.sha256(данные).hexdigest()
        for бюджет, код, ожидаемый in ((True,3,хэш),(0,3,хэш),(16000,2,хэш),(16000,True,хэш),(16000,3,'0'*64)):
            with проверка.subTest(бюджет=бюджет,код=код), проверка.assertRaises(ValueError):
                потребить(данные, ожидаемый, бюджет, код)

    def test_неизвестный_и_повреждённый_формат_отклоняются_до_вывода(проверка):
        for бюджет in (16000, 1000000):
            for данные in (b'{}\n', b'{"x":1,"x":2}\n', b'\xff'):
                with проверка.subTest(бюджет=бюджет,данные=данные), проверка.assertRaises(ValueError):
                    потребить(данные, hashlib.sha256(данные).hexdigest(), бюджет, 3)

    def test_непомещающийся_оригинал_не_усекается(проверка):
        значение=снимок(); значение['сообщения'][0]['содержимое'][0]['text']='ё'*20000
        with проверка.assertRaisesRegex(ValueError, 'бюджет'):
            проверка.вызвать(байты(значение), число=1)

    def test_неполнота_и_детерминизм_не_скрываются(проверка):
        значение=снимок(); значение['полнота_источника']=False; значение['непроверенный_хвост']=9
        первый=проверка.вызвать(байты(значение)); второй=проверка.вызвать(байты(значение))
        проверка.assertEqual(первый,второй)
        проверка.assertEqual(json.loads(первый[0])['состояние']['непроверенный_хвост'],9)

    def test_командный_вход_разделяет_вывод_и_квитанцию(проверка):
        with tempfile.TemporaryDirectory() as каталог:
            путь=Path(каталог)/'остаток.json'; данные=байты(снимок()); путь.write_bytes(данные)
            команда=[sys.executable,'-B',str(Path(__file__).resolve().parents[1]/'scripts/потребить-остаток.py'),
                '--результат',str(путь),'--sha256',hashlib.sha256(данные).hexdigest(),
                '--код-производителя','3','--бюджет-байтов','16000']
            результат=subprocess.run(команда,capture_output=True)
            проверка.assertEqual(результат.returncode,0,результат.stderr)
            проверка.assertEqual(json.loads(результат.stderr)['реакция'],'компактный-остаток')
            проверка.assertLessEqual(len(результат.stdout),16000)
            отказ=subprocess.run(команда+['--бюджет-байтов','100'],capture_output=True)
            проверка.assertEqual(отказ.returncode,2)
            проверка.assertEqual(отказ.stdout,b'')
            проверка.assertEqual(путь.read_bytes(),данные)
            проверка.assertEqual(list(Path(каталог).iterdir()),[путь])

    def test_код_производителя_соответствует_состоянию(проверка):
        данные=байты(снимок())
        with проверка.assertRaisesRegex(ValueError, 'код производителя'):
            потребить(данные,hashlib.sha256(данные).hexdigest(),16000,0)
        значение=снимок(); значение['остаток']=[]; значение['разбор_сообщений_завершён']=True
        данные=байты(значение)
        with проверка.assertRaisesRegex(ValueError, 'код производителя'):
            потребить(данные,hashlib.sha256(данные).hexdigest(),16000,3)
        вывод,квитанция=потребить(данные,hashlib.sha256(данные).hexdigest(),16000,0)
        проверка.assertEqual(квитанция['источник']['код_производителя'],0)

    def test_точный_предел_страницы_с_переводом_строки(проверка):
        данные=байты(снимок());хэш=hashlib.sha256(данные).hexdigest()
        вывод,_=потребить(данные,хэш,16000,3)
        проверка.assertTrue(вывод.endswith(b'\n'))
        проверка.assertEqual(потребить(данные,хэш,len(вывод),3)[0],вывод)
        with проверка.assertRaisesRegex(ValueError,'бюджет'):
            потребить(данные,хэш,len(вывод)-1,3)

    def test_квитанция_не_копирует_произвольное_поле_задачи(проверка):
        for задача in (None, 'произвольная нагрузка'*1000):
            значение=снимок();значение['задача']=задача
            for бюджет in (16000,1000000):
                with проверка.subTest(задача=type(задача),бюджет=бюджет), проверка.assertRaises(ValueError):
                    данные=байты(значение)
                    потребить(данные,hashlib.sha256(данные).hexdigest(),бюджет,3)

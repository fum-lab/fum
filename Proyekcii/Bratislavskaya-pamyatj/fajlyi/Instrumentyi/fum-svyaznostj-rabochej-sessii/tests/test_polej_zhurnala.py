"""Ранний вход выявляет известные пропуски без полного обхода репозитория."""

import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

from фикстура_полей_журнала import создать_пару

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import проверка_полей_журнала as проверка


class ПроверкиПолейЖурнала(unittest.TestCase):
    def test_обе_роли_должны_быть_прямо_в_разделе_затронутых_файлов(сам):
        сам.подготовить()
        исходный = сам.запрос.read_text()
        for имя, подпись in (("запрос.md", "Запрос"), ("отчёт.md", "Отчёт")):
            ссылка = f"- [{подпись}]({имя})."
            for замена in ("", "- [Каталог](.).", f"<!-- {ссылка} -->",
                           "- Снят с Git-учёта и сохранён локально: `" + сам.запрос.with_name(имя).relative_to(сам.корень).as_posix() + "`",
                           f"```text\n{ссылка}\n```"):
                with сам.subTest(имя=имя, замена=замена):
                    текст = исходный.replace(ссылка, замена)
                    текст = текст.replace("## Повлиял на файлы", ссылка + "\n\n## Повлиял на файлы")
                    сам.запрос.write_text(текст)
                    ошибки = проверка.проверить(сам.корень, сам.запрос)["ошибки"]
                    сам.assertTrue(any("Повлиял на файлы" in ошибка and имя in ошибка for ошибка in ошибки), ошибки)

    def подготовить(сам):
        сам.корень = Path(сам.enterContext(tempfile.TemporaryDirectory())).resolve()
        сам.запрос = создать_пару(сам.корень)
        сам.отчёт = сам.запрос.with_name("отчёт.md")

    def test_правильная_пара_возвращает_два_отпечатка_без_финальной_приёмки(сам):
        сам.подготовить()
        результат = проверка.проверить(сам.корень, сам.запрос)
        сам.assertEqual(результат["ошибки"], [])
        сам.assertFalse(результат["полная_приёмка"])
        сам.assertEqual(len(результат["входы"]), 2)
        for запись in результат["входы"]:
            исходник = (сам.корень / запись["путь"]).read_bytes()
            сам.assertEqual(запись["sha256"], hashlib.sha256(исходник).hexdigest())
            сам.assertEqual(запись["байтов"], len(исходник))

    def test_оба_известных_пропуска_и_скрытая_граница_отклоняются(сам):
        сам.подготовить()
        исходный = сам.отчёт.read_text()
        for старое, новое, фрагмент in [
            ("Границы и способ измерения", "Граница", "table columns"),
            ("Граница профиля: только синтетический пример.", "", "boundary line"),
            ("Граница профиля: только синтетический пример.",
             "```text\nГраница профиля: скрыто.\n```", "boundary line"),
        ]:
            with сам.subTest(новое=новое):
                сам.отчёт.write_text(исходный.replace(старое, новое))
                сам.assertIn(фрагмент, "\n".join(проверка.проверить(сам.корень, сам.запрос)["ошибки"]))

    def test_сумма_инструменты_и_ссылка_не_теряются_при_раннем_вызове(сам):
        сам.подготовить()
        сам.отчёт.write_text(сам.отчёт.read_text().replace("проверок: 1 с", "проверок: 2 с") + "\n[Нет](нет.md)\n")
        сам.запрос.write_text(сам.запрос.read_text().replace("fum-moskovskoye-vremya-rabochej-sessii", "Пример"))
        ошибки = "\n".join(проверка.проверить(сам.корень, сам.запрос)["ошибки"])
        for фрагмент in ("total", "fum-moskovskoye-vremya", "broken Markdown link"):
            сам.assertIn(фрагмент, ошибки)

    def test_не_запускает_глобальные_проверки_гит_и_чтение_целей(сам):
        сам.подготовить()
        исходное = Path.read_text
        прочитано = []

        def прочитать(путь, *аргументы, **параметры):
            прочитано.append(путь)
            сам.assertIn(путь, {сам.запрос, сам.отчёт})
            return исходное(путь, *аргументы, **параметры)

        with mock.patch.object(проверка.связность, "project_markdown_paths", side_effect=AssertionError("Полный обход")), \
             mock.patch.object(проверка.связность, "проверить_машинный_отчёт_о_запусках", side_effect=AssertionError("Полная приёмка")), \
             mock.patch.object(subprocess, "run", side_effect=AssertionError("Подпроцесс")), \
             mock.patch.object(Path, "read_text", прочитать):
            сам.assertEqual(проверка.проверить(сам.корень, сам.запрос)["ошибки"], [])
        сам.assertTrue(прочитано)

    def test_отсутствующий_отчёт_и_выход_за_корень_отклоняются(сам):
        сам.подготовить()
        сам.отчёт.unlink()
        with сам.assertRaises(ValueError):
            проверка.проверить(сам.корень, сам.запрос)
        with сам.assertRaises(ValueError):
            проверка.проверить(сам.корень, сам.корень.parent / "запрос.md")

    def test_символическая_ссылка_не_читается(сам):
        сам.подготовить()
        исходный = сам.корень / "другой.md"
        сам.отчёт.rename(исходный)
        сам.отчёт.symlink_to(исходный)
        with сам.assertRaises(ValueError):
            проверка.проверить(сам.корень, сам.запрос)

    def test_изменение_документа_в_ходе_проверки_отклоняется(сам):
        сам.подготовить()
        исходное = проверка.связность.validate_markdown_links

        def изменить(пути, корень):
            результат = исходное(пути, корень)
            сам.отчёт.write_text(сам.отчёт.read_text() + "\nИзменение.\n")
            return результат

        with mock.patch.object(проверка.связность, "validate_markdown_links", изменить):
            with сам.assertRaises(ValueError):
                проверка.проверить(сам.корень, сам.запрос)

    def test_командный_вход_возвращает_структурированный_отказ(сам):
        сам.подготовить()
        сценарий = Path(__file__).resolve().parents[1] / "scripts/проверить-поля-журнала.py"
        команда = [sys.executable, "-B", str(сценарий), "--корень", str(сам.корень), "--запрос", str(сам.запрос)]
        успешный = subprocess.run(команда, capture_output=True, text=True)
        сам.assertEqual(успешный.returncode, 0, успешный.stderr)
        сам.assertFalse(json.loads(успешный.stdout)["полная_приёмка"])
        сам.отчёт.write_text(сам.отчёт.read_text().replace("Границы и способ измерения", "Граница"))
        отказ = subprocess.run(команда, capture_output=True, text=True)
        сам.assertEqual(отказ.returncode, 1, отказ.stderr)
        сам.assertTrue(json.loads(отказ.stdout)["ошибки"])

    def test_маркер_в_дословной_команде_не_считается_незаполненным_шаблоном(сам):
        сам.подготовить()
        сам.запрос.write_text(сам.запрос.read_text().replace(
            "Проверить поля.\n", "Проверить поля.\n<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->\n"))
        сам.assertEqual(проверка.проверить(сам.корень, сам.запрос)["ошибки"], [])

    def test_подмена_папки_ссылкой_отклоняется_даже_при_тех_же_байтах(сам):
        сам.подготовить()
        исходное = проверка.связность.validate_markdown_links

        def заменить_каталог(пути, корень):
            результат = исходное(пути, корень)
            прежняя = сам.запрос.parent
            другая = прежняя.with_name("копия")
            прежняя.rename(другая)
            прежняя.symlink_to(другая, target_is_directory=True)
            return результат

        with mock.patch.object(проверка.связность, "validate_markdown_links", заменить_каталог):
            with сам.assertRaises(ValueError):
                проверка.проверить(сам.корень, сам.запрос)

    def test_комментарий_и_дословная_команда_не_заменяют_прямую_ссылку(сам):
        сам.подготовить()
        исходный = сам.отчёт.read_text()
        for замена in ("<!-- [Исходный запрос](запрос.md). -->",
                       "```text\n[Исходный запрос](запрос.md).\n```"):
            with сам.subTest(замена=замена):
                сам.отчёт.write_text(исходный.replace("[Исходный запрос](запрос.md).", замена))
                сам.assertIn("Нет прямой ссылки", "\n".join(проверка.проверить(сам.корень, сам.запрос)["ошибки"]))
        сам.отчёт.write_text(исходный)
        сам.запрос.write_text(сам.запрос.read_text().replace(
            "Проверить поля.\n", "[Отчёт](отчёт.md).\n").replace("- [Отчёт](отчёт.md).\n", ""))
        сам.assertIn("Нет прямой ссылки", "\n".join(проверка.проверить(сам.корень, сам.запрос)["ошибки"]))

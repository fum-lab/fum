"""План не пишет; применение сохраняет точные части и наблюдаемый префикс."""
import unittest
from unittest import mock

import test_обработка_сообщений as основа
import устойчивые_свидетельства as модуль


class ПроверкаСвидетельств(unittest.TestCase):
    def setUp(проверка):
        основа.ПроверкаОбработки.setUp(проверка)
    гит = основа.ПроверкаОбработки.гит
    коммит = основа.ПроверкаОбработки.коммит
    добавить = основа.ПроверкаОбработки.добавить
    остаток = основа.ПроверкаОбработки.остаток
    свидетельство = основа.ПроверкаОбработки.свидетельство

    def решения(проверка):
        снимок = проверка.остаток()
        return [{"экземпляр": сообщение["экземпляр"], "решение": "работа", "актуальность": "актуально", "поздние": [],
                 "допустимые_части_sha256": модуль.обработка.хэш(модуль.читатель._байты(сообщение["содержимое"])),
                 "ответ": проверка.свидетельство(проверка.отчёт, "Команда принята в работу.\n"),
                 "основание": проверка.свидетельство(проверка.отчёт, "Сначала сохранение оригинала.\n")}
                for сообщение in снимок["сообщения"]]

    def план(проверка, решения=None):
        return модуль.подготовить(проверка.источник, основа.ЗАДАЧА, корень_репозитория=проверка.корень,
            каталог="Журнал/пример/материалы/свидетельства", решения=решения or проверка.решения())

    def применить(проверка, план):
        return модуль.применить(проверка.источник, основа.ЗАДАЧА, корень_репозитория=проверка.корень,
            кэш=проверка.кэш, план=план, ожидаемый_хэш=модуль.обработка.хэш(модуль.читатель._байты(план)))

    def test_план_без_записи_навигация_повтор(проверка):
        до = проверка.гит("status", "--porcelain")
        план = проверка.план()
        проверка.assertEqual(до, проверка.гит("status", "--porcelain"))
        итог = проверка.применить(план)
        проверка.assertTrue(итог["применено"])
        проверка.assertFalse(итог["завершение_задачи_доказано"])
        история = проверка.путь_истории.read_bytes()
        with (проверка.корень / проверка.запрос).open("w") as поток:
            поток.write("## Навигация по запросам\nНовый сосед.\nСделай.\n")
        (проверка.корень / проверка.отчёт).write_text("Отчёт обновлён после сохранения.\n")
        проверка.assertEqual([], проверка.остаток()["остаток"])
        проверка.assertTrue(проверка.применить(план)["применено"])
        проверка.assertEqual(история, проверка.путь_истории.read_bytes())

    def test_полные_части_и_выбор_экземпляра(проверка):
        проверка.добавить("", 2, части=[{"type":"input_text","text":"Ёж\n"}, {"type":"input_image","image_url":"https://example.invalid/image.png"}], виды=["user.text", "user.image"])
        решения = проверка.решения()
        план = проверка.план([решения[1]])
        проверка.assertTrue(проверка.применить(план)["применено"])
        проверка.assertEqual([решения[0]["экземпляр"]], [э["экземпляр"] for э in проверка.остаток()["остаток"]])
        проверка.assertIn('input_image', план["файлы"][0]["текст"])

    def test_поздний_ввод_отказывает_до_записи(проверка):
        план = проверка.план()
        проверка.добавить("Новое.\n", 2)
        with проверка.assertRaises(модуль.обработка.ОшибкаОбработки):
            проверка.применить(план)
        проверка.assertFalse((проверка.корень / план["каталог"]).exists())

    def test_отказ_публикационного_выбора(проверка):
        решения = проверка.решения()
        решения[0]["допустимые_части_sha256"] = "0" * 64
        with проверка.assertRaises(модуль.обработка.ОшибкаОбработки):
            проверка.план(решения)

    def test_подмена_плана_отказывает(проверка):
        план = проверка.план()
        отпечаток = модуль.обработка.хэш(модуль.читатель._байты(план))
        план["файлы"][0]["текст"] += "Подмена"
        with проверка.assertRaises(модуль.обработка.ОшибкаОбработки):
            модуль.применить(проверка.источник, основа.ЗАДАЧА, корень_репозитория=проверка.корень, кэш=проверка.кэш, план=план, ожидаемый_хэш=отпечаток)

    def test_частичное_применение_и_повтор(проверка):
        проверка.добавить("Сделай.\n", 2)
        план = проверка.план()
        настоящий = модуль.обработка.сохранить_обработку
        число = 0
        def прервать(*аргументы, **параметры):
            nonlocal число
            число += 1
            if число == 2:
                raise OSError("Открытый отказ")
            return настоящий(*аргументы, **параметры)
        with mock.patch.object(модуль.обработка, "сохранить_обработку", side_effect=прервать):
            итог = проверка.применить(план)
        проверка.assertFalse(итог["применено"])
        проверка.assertEqual(1, len(итог["результаты"]))
        проверка.assertTrue(проверка.применить(план)["применено"])
        проверка.assertEqual([], проверка.остаток()["остаток"])

    def test_смена_вершины_отказывает(проверка):
        план = проверка.план()
        (проверка.корень / "новый").write_text("Новый коммит")
        проверка.коммит()
        with проверка.assertRaises(модуль.обработка.ОшибкаОбработки):
            проверка.применить(план)

    def test_повреждение_материала_не_перезаписывается(проверка):
        план = проверка.план()
        проверка.применить(план)
        путь = проверка.корень / план["файлы"][0]["путь"]
        путь.write_text("Повреждение")
        with проверка.assertRaises(модуль.обработка.ОшибкаОбработки):
            проверка.применить(план)
        проверка.assertEqual("Повреждение", путь.read_text())

    def test_смена_истории_отказывает_до_материалов(проверка):
        план = проверка.план()
        снимок = проверка.остаток()
        запись = основа.ПроверкаОбработки.предложение(проверка, снимок)
        основа.МОДУЛЬ.сохранить_обработку(проверка.источник, основа.ЗАДАЧА, корень_репозитория=проверка.корень, кэш=проверка.кэш, запись=запись, ожидаемая_история=снимок["история_sha256"])
        with проверка.assertRaises(модуль.обработка.ОшибкаОбработки):
            проверка.применить(план)
        проверка.assertFalse((проверка.корень / план["каталог"]).exists())

    def test_сбой_после_атомарной_записи_повторяет_без_дубля(проверка):
        план = проверка.план()
        настоящий = модуль.обработка.сохранить_обработку
        def потерять_ответ(*аргументы, **параметры):
            настоящий(*аргументы, **параметры)
            raise OSError("Ответ утрачен")
        with mock.patch.object(модуль.обработка, "сохранить_обработку", side_effect=потерять_ответ):
            итог = проверка.применить(план)
        проверка.assertFalse(итог["применено"])
        до = проверка.путь_истории.read_bytes()
        проверка.assertTrue(проверка.применить(план)["применено"])
        проверка.assertEqual(до, проверка.путь_истории.read_bytes())

    def test_кли_план_и_применение(проверка):
        import json
        import subprocess
        import sys
        описание = проверка.каталог / "описание.json"
        описание.write_bytes(модуль.читатель._байты({"каталог":"Журнал/пример/материалы/свидетельства", "решения": проверка.решения()}))
        описание.chmod(0o600)
        команда = [sys.executable, "-B", str(основа.КАТАЛОГ / "подготовить-свидетельства.py"), "--корень-репозитория", str(проверка.корень), "--исходник", str(проверка.источник), "--codex-thread-id", основа.ЗАДАЧА]
        результат = subprocess.run([*команда, "план", "--описание", str(описание)], capture_output=True)
        проверка.assertEqual(0, результат.returncode, результат.stderr)
        оболочка = json.loads(результат.stdout)
        путь = проверка.каталог / "план.json"
        путь.write_bytes(модуль.читатель._байты(оболочка["план"]))
        путь.chmod(0o600)
        итог = subprocess.run([*команда, "применить", "--план", str(путь), "--ожидаемый-sha256", оболочка["sha256"], "--кэш", str(проверка.кэш)], capture_output=True)
        проверка.assertEqual(0, итог.returncode, итог.stderr)
        проверка.assertTrue(json.loads(итог.stdout)["применено"])

    def test_повтор_завершает_синхронизацию_материала(проверка):
        план = проверка.план()
        настоящий = модуль.читатель._установить
        число = 0
        def прервать(*аргументы, **параметры):
            nonlocal число
            настоящий(*аргументы, **параметры)
            число += 1
            if число == 1:
                raise OSError("Сбой после установки материала")
        with mock.patch.object(модуль.читатель, "_установить", side_effect=прервать):
            проверка.assertFalse(проверка.применить(план)["применено"])
        with mock.patch.object(модуль.os, "fsync", wraps=модуль.os.fsync) as синхронизация:
            модуль.установить(проверка.корень, план["файлы"][0])
            проверка.assertGreaterEqual(синхронизация.call_count, 2)
        проверка.assertTrue(проверка.применить(план)["применено"])

    def test_недопустимый_кэш_отказывает_до_материалов(проверка):
        план = проверка.план()
        with проверка.assertRaises(ValueError):
            модуль.применить(проверка.источник, основа.ЗАДАЧА, корень_репозитория=проверка.корень,
                кэш=проверка.корень / "кэш.json", план=план, ожидаемый_хэш=модуль.обработка.хэш(модуль.читатель._байты(план)))
        проверка.assertFalse((проверка.корень / план["каталог"]).exists())

    def test_позднее_основание_сохраняется_с_обоими_экземплярами(проверка):
        проверка.добавить("Позднее уточнение.\n", 2)
        решения = проверка.решения()
        решения[0]["актуальность"] = "уточнено"
        решения[0]["поздние"] = [решения[1]["экземпляр"]]
        план = проверка.план(решения)
        проверка.assertTrue(проверка.применить(план)["применено"])
        проверка.assertEqual([решения[1]["экземпляр"]], план["записи"][0]["поздние"])
        команды = [файл for файл in план["файлы"] if файл["путь"].endswith("/команда.json")]
        проверка.assertEqual(2, len(команды))
        проверка.assertEqual(модуль.читатель._байты([{"type":"input_text","text":"Позднее уточнение.\n"}]), (проверка.корень / команды[1]["путь"]).read_bytes())
        (проверка.корень / проверка.запрос).write_text("Новая навигация.\n")
        (проверка.корень / проверка.отчёт).write_text("Обновлённый отчёт.\n")
        проверка.assertEqual([], проверка.остаток()["остаток"])
        проверка.assertTrue(проверка.применить(план)["применено"])

    def test_невыбранное_позднее_основание_не_обрабатывается(проверка):
        проверка.добавить("Позднее уточнение.\n", 2)
        решения = проверка.решения()
        решения[0]["актуальность"] = "отменено"
        решения[0]["поздние"] = [решения[1]["экземпляр"]]
        план = проверка.план([решения[0]])
        проверка.assertTrue(проверка.применить(план)["применено"])
        проверка.assertEqual([решения[1]["экземпляр"]], [э["экземпляр"] for э in проверка.остаток()["остаток"]])
        проверка.assertEqual(1, len([файл for файл in план["файлы"] if файл["путь"].endswith("/команда.json")]))

"""Явная передача двух пояснений; подтверждение относится к декодеру, не модели."""
import copy
import hashlib
import json
from pathlib import Path
from uuid import UUID

from компактный_остаток import закодировать, объект, требовать

ЗАКРЕПЛЁННЫЙ_ХЭШ = "8e1f2fd34c04c2937137388951ec0654b85cb06b6bb4326ed9da386fcd70080e"
НЕ_ПЕРЕДАНО = object()


def действительное_определение(значение):
    if not isinstance(значение, dict) or set(значение) != {"схема", "версия", "значения", "sha256"}:
        return False
    if значение["схема"] != "fum.определение-пояснений.1" or type(значение["версия"]) is not int or значение["версия"] != 1:
        return False
    if значение["sha256"] != ЗАКРЕПЛЁННЫЙ_ХЭШ:
        return False
    try:
        содержимое = {ключ: часть for ключ, часть in значение.items() if ключ != "sha256"}
        return hashlib.sha256(закодировать(содержимое)).hexdigest() == ЗАКРЕПЛЁННЫЙ_ХЭШ
    except (ValueError, TypeError, RecursionError):
        return False


def загрузить_определение():
    try:
        путь = Path(__file__).resolve().parents[1] / "профили/пояснения-ответа-1.json"
        значение = json.loads(путь.read_bytes(), object_pairs_hook=объект)
        return значение if действительное_определение(значение) else None
    except (OSError, ValueError, RecursionError):
        return None


def действительная_передача(значение):
    try:
        return isinstance(значение, str) and str(UUID(значение)) == значение
    except ValueError:
        return False


def ссылка(определение):
    return {ключ: определение[ключ] for ключ in ("версия", "sha256")}


def действительная_ссылка(значение, определение):
    return (isinstance(значение, dict) and type(значение.get("версия")) is int
        and значение == ссылка(определение))


def подготовить_подтверждение(определение, подтверждение, передача):
    """Получатель вызывает заново перед запросом, передавая доступное ему определение."""
    if not действительное_определение(определение) or not действительная_передача(передача):
        return None
    ожидаемое = {"схема": "fum.подтверждение-пояснений.1", "передача": передача, **ссылка(определение)}
    if not isinstance(подтверждение, dict) or type(подтверждение.get("версия")) is not int or подтверждение != ожидаемое:
        return None
    return copy.deepcopy(подтверждение)


def подтвердить(полная_выдача, передача):
    """Отдельное явное действие после получения полной формы; отправитель его не вызывает."""
    требовать(isinstance(полная_выдача, dict) and полная_выдача.get("схема") == "fum.передача-ответа.1"
        and полная_выдача.get("форма") == "полная" and полная_выдача.get("передача") == передача
        and действительная_передача(передача), "Нужна полученная полная форма для этой передачи")
    определение = полная_выдача.get("определение")
    требовать(действительное_определение(определение)
        and действительная_ссылка(полная_выдача.get("профиль"), определение), "Неизвестное или повреждённое определение")
    return {"схема": "fum.подтверждение-пояснений.1", "передача": передача, **ссылка(определение)}


def упаковать(полный, передача=None, подтверждение=None, *, определение=НЕ_ПЕРЕДАНО):
    требовать(isinstance(полный, dict), "Ожидался полный объект ответа")
    if определение is НЕ_ПЕРЕДАНО:
        определение = загрузить_определение()
    if not действительное_определение(определение):
        определение = None
    подтверждено = подготовить_подтверждение(определение, подтверждение, передача) is not None
    снимок = полный.get("полный_снимок")
    сокращать = (подтверждено and полный.get("схема") == "fum.срез-ответа-задачи.1"
        and isinstance(снимок, dict)
        and снимок.get("формат") == определение["значения"]["/полный_снимок/формат"]
        and полный.get("граница") == определение["значения"]["/граница"])
    данные = copy.deepcopy(полный)
    if сокращать:
        del данные["полный_снимок"]["формат"]
        del данные["граница"]
    return {"схема": "fum.передача-ответа.1", "передача": передача if действительная_передача(передача) else None,
        "форма": "ссылочная" if сокращать else "полная", "данные": данные,
        "профиль": ссылка(определение) if определение is not None else None,
        "определение": None if сокращать else copy.deepcopy(определение)}


def восстановить(выдача, определение=None, передача=None):
    требовать(isinstance(выдача, dict) and set(выдача) == {"схема", "передача", "форма", "данные", "профиль", "определение"}
        and выдача["схема"] == "fum.передача-ответа.1" and isinstance(выдача["данные"], dict), "Неизвестный конверт ответа")
    данные = copy.deepcopy(выдача["данные"])
    if выдача["форма"] == "полная":
        return данные
    требовать(выдача["форма"] == "ссылочная", "Неизвестная форма ответа")
    требовать(действительное_определение(определение) and действительная_передача(передача)
        and выдача["передача"] == передача and действительная_ссылка(выдача["профиль"], определение)
        and выдача["определение"] is None, "Определение недоступно: запросите полную форму без подтверждения")
    требовать(данные.get("схема") == "fum.срез-ответа-задачи.1" and isinstance(данные.get("полный_снимок"), dict)
        and "формат" not in данные["полный_снимок"] and "граница" not in данные, "Конфликт восстанавливаемых полей")
    данные["полный_снимок"]["формат"] = определение["значения"]["/полный_снимок/формат"]
    данные["граница"] = определение["значения"]["/граница"]
    return данные

"""Наблюдения model/effort без экспорта содержимого native JSONL."""
import copy
import hashlib
import os
from pathlib import Path
import re
import time
import uuid
from contextlib import nullcontext

import сообщения_задачи as чтение


_СХЕМА = "fum.история-модели.1"
_РЕАЛИЗАЦИЯ = чтение._хэш(Path(__file__).read_bytes() + Path(чтение.__file__).read_bytes())


def _путь(значение):
    путь = Path(значение).absolute()
    for предок in (путь, *путь.parents):
        чтение._требовать(not предок.is_symlink(), "символическая ссылка в пути")
    чтение._требовать(".." not in путь.parts, "родительский переход в пути запрещён")
    return путь


def _прочитать(путь, приватный=False):
    with путь.open("rb") as поток:
        чтение._обычный(os.fstat(поток.fileno()), приватный=приватный)
        return поток.read()


def _строка(значение):
    return isinstance(значение, str) and bool(значение) and len(значение) <= 256 and all(
        ord(символ) >= 32 and символ not in "\x7f\u2028\u2029" for символ in значение)


def _событие(история, запись, сырая, начало, конец):
    позиция = {"начало": начало, "конец": конец, "sha256": чтение._хэш(сырая)}
    if not isinstance(запись, dict):
        история["пропуски"].append({"позиция": позиция, "вид": "повреждённая строка JSONL"})
        история["последнее"] = None
        return
    if запись.get("type") != "turn_context":
        return
    данные = запись.get("payload")
    if not isinstance(данные, dict) or not all(_строка(данные.get(ключ)) for ключ in ("model", "effort")) or not _строка(запись.get("timestamp")):
        доступное = данные if isinstance(данные, dict) else {}
        история["пропуски"].append({"позиция": позиция, "вид": "неполное наблюдение turn_context",
            "модель": доступное.get("model") if _строка(доступное.get("model")) else "unknown",
            "усилие": доступное.get("effort") if _строка(доступное.get("effort")) else "unknown",
            "время": запись.get("timestamp") if _строка(запись.get("timestamp")) else "unknown"})
        история["последнее"] = None
        return
    наблюдение = {"модель": данные["model"], "усилие": данные["effort"],
        "время": запись["timestamp"], "позиция": позиция, "причина": "unknown", "инициатор": "unknown"}
    предыдущее = история["последнее"]
    if предыдущее is None or any(предыдущее[ключ] != наблюдение[ключ] for ключ in ("модель", "усилие")):
        история["события"].append({**наблюдение, "предыдущее": None if предыдущее is None else
            {ключ: предыдущее[ключ] for ключ in ("модель", "усилие")}, "вид": "первое наблюдение" if история["число_наблюдений"] == 0 else
            "наблюдение после пропуска" if предыдущее is None else "смена наблюдаемой пары"})
    история["число_наблюдений"] += 1
    история["последнее"] = наблюдение


def _приём(поток, задача, прежний, размер, профиль):
    история = copy.deepcopy(прежний) if прежний else {"схема": _СХЕМА, "задача": задача,
        "источник": None, "граница": 0, "sha256": None, "число_наблюдений": 0,
        "события": [], "пропуски": [], "последнее": None,
        "переключения_между_наблюдениями_известны": False}
    хэш = hashlib.sha256()
    if прежний:
        чтение._требовать(размер >= прежний["размер_снимка"], "источник усечён")
        осталось = прежний["граница"]
        while осталось:
            блок = поток.read(min(осталось, 1024 * 1024))
            чтение._требовать(bool(блок), "источник усечён")
            хэш.update(блок)
            осталось -= len(блок)
            профиль["прочитано_байтов"] += len(блок)
        чтение._требовать(хэш.hexdigest() == прежний["sha256"], "ранее прочитанный префикс изменён")
    while поток.tell() < размер:
        начало = поток.tell()
        сырая = поток.readline(min(чтение._МАКСИМУМ_СТРОКИ + 1, размер - начало))
        профиль["прочитано_байтов"] += len(сырая)
        чтение._требовать(len(сырая) <= чтение._МАКСИМУМ_СТРОКИ, "строка превышает 64 МиБ")
        if not сырая.endswith(b"\n"):
            break
        профиль["разобрано_строк"] += 1
        try:
            запись = чтение._разобрать(сырая)
        except чтение.ОшибкаСообщений:
            запись = None
        if начало == 0:
            чтение._требовать(isinstance(запись, dict) and запись.get("type") == "session_meta" and
                isinstance(запись.get("payload"), dict) and запись["payload"].get("id") == задача,
                "неверная идентичность native задачи")
            история["источник"] = чтение._хэш(сырая)
        else:
            чтение._требовать(not isinstance(запись, dict) or запись.get("type") != "session_meta", "повторная идентичность задачи")
            _событие(история, запись, сырая, начало, поток.tell())
        хэш.update(сырая)
        история["граница"] = поток.tell()
    чтение._требовать(история["источник"] is not None, "нет завершённого session_meta")
    история.update(sha256=хэш.hexdigest(), размер_снимка=размер,
                    неполный_хвост=размер - история["граница"])
    return история


def импортировать(источник, задача, *, корень_репозитория, кэш, история, без_записи=False):
    """Полный приём, атомарная история и приватный курсор; ответ всегда компактный.

    После сбоя между историей и курсором повтор допускает только точный уже
    установленный результат. Префикс хэшируется при росте, JSON разбирается
    только в хвосте. Неизменный stat допускает нулевое чтение источника.
    """
    начало = time.perf_counter_ns()
    чтение._требовать(str(uuid.UUID(задача)) == задача, "неканонический UUID")
    корень = _путь(корень_репозитория)
    исходник, курсор, назначение = map(_путь, (источник, кэш, история))
    чтение._требовать(назначение.is_relative_to(корень), "история вне своего checkout")
    чтение._требовать(not курсор.is_relative_to(корень) and not any(
        os.path.lexists(предок / ".git") for предок in курсор.parents), "курсор должен быть вне Git")
    чтение._требовать(len({исходник, курсор, назначение}) == 3, "совпадающие пути")
    чтение._требовать(курсор.parent.is_dir() and назначение.parent.is_dir(), "родительский каталог отсутствует")
    with nullcontext() if без_записи else чтение._замок(курсор):
        старое = _прочитать(назначение) if назначение.exists() else None
        прежний = None
        if курсор.exists():
            оболочка = чтение._разобрать(_прочитать(курсор, True))
            чтение._требовать(set(оболочка) == {"данные", "sha256"}, "неверный курсор")
            прежний = оболочка["данные"]
            чтение._требовать(чтение._хэш(чтение._байты(прежний)) == оболочка["sha256"], "повреждённый курсор")
            чтение._требовать(set(прежний) == {"история", "метка", "назначение", "реализация", "ожидаемый_sha256", "подготовлено"} and
                прежний["история"]["задача"] == задача and прежний["история"]["схема"] == _СХЕМА and
                прежний["назначение"] == str(назначение), "чужой курсор")
            чтение._требовать(прежний["реализация"] == _РЕАЛИЗАЦИЯ, "реализация изменилась; нужен новый курсор и отдельная сверка истории")
        профиль = {"прочитано_байтов": 0, "разобрано_строк": 0}
        начало_чтения = time.perf_counter_ns()
        with os.fdopen(os.open(исходник, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
            состояние = os.fstat(поток.fileno())
            чтение._обычный(состояние)
            if прежний:
                чтение._требовать(прежний["метка"][:2] == чтение._метка(состояние)[:2], "источник заменён")
            if прежний and прежний["метка"] == чтение._метка(состояние):
                данные = copy.deepcopy(прежний["история"])
            else:
                данные = _приём(поток, задача, прежний["история"] if прежний else None, состояние.st_size, профиль)
            дописано, проверено = чтение._сверить_снимок(поток, исходник, состояние, данные)
            профиль["прочитано_байтов"] += проверено
        профиль["чтение_наносекунды"] = time.perf_counter_ns() - начало_чтения
        байты = чтение._байты(данные)
        if старое is not None and старое != байты:
            чтение._требовать(прежний is not None and (старое == чтение._байты(прежний["история"]) or
                прежний["подготовлено"] and чтение._хэш(старое) == прежний["ожидаемый_sha256"]),
                "история не совпадает с курсором или подготовленной записью; нужна сверка")
        if прежний and старое is None:
            чтение._требовать(прежний["подготовлено"] and прежний["ожидаемый_sha256"] is None,
                             "история исчезла; нужна сверка")
        новое = {"история": данные, "метка": чтение._метка(состояние),
                 "назначение": str(назначение), "реализация": _РЕАЛИЗАЦИЯ,
                 "подготовлено": False, "ожидаемый_sha256": None}
        начало_записи = time.perf_counter_ns()
        if not без_записи:
            if старое != байты:
                подготовленное = {**новое, "подготовлено": True,
                    "ожидаемый_sha256": чтение._хэш(старое) if старое is not None else None}
                чтение._установить(курсор, чтение._байты({"данные": подготовленное,
                    "sha256": чтение._хэш(чтение._байты(подготовленное))}))
                чтение._установить(назначение, байты)
            if прежний != новое:
                чтение._установить(курсор, чтение._байты({"данные": новое, "sha256": чтение._хэш(чтение._байты(новое))}))
        профиль["сохранение_наносекунды"] = time.perf_counter_ns() - начало_записи
        профиль["всего_наносекунды"] = time.perf_counter_ns() - начало
        return {"схема": "fum.приём-истории-модели.1", "задача": задача,
            "новых_наблюдений": данные["число_наблюдений"] - (прежний["история"]["число_наблюдений"] if прежний else 0),
            "число_наблюдений": данные["число_наблюдений"], "событий": len(данные["события"]),
            "пропусков": len(данные["пропуски"]), "последнее": данные["последнее"],
            "неполный_хвост": данные["неполный_хвост"], "дописано_после_снимка": дописано,
            "полнота": not данные["пропуски"] and not данные["неполный_хвост"] and not дописано,
            "переключения_между_наблюдениями_известны": False,
            "история_sha256": чтение._хэш(байты), "изменения_нужны": старое != байты,
            "без_записи": без_записи, "профиль": профиль}


def подготовить_коммит(основа, результат, корневая_задача):
    """Добавить наблюдаемые поля перед единственным последним trailer."""
    трейлер = "Codex-Thread-ID: " + корневая_задача
    чтение._требовать(str(uuid.UUID(корневая_задача)) == корневая_задача and
        основа.rstrip().endswith(трейлер) and len(re.findall(r"^Codex-Thread-ID:", основа, re.M)) == 1,
        "нужен единственный последний корневой trailer")
    чтение._требовать(результат["полнота"] and результат["последнее"] is not None, "нет полного последнего наблюдения")
    наблюдение = результат["последнее"]
    начало, конец = "Наблюдаемые метаданные Codex:", "Конец наблюдаемых метаданных Codex."
    блок = (начало + "\nmodel: " + наблюдение["модель"] + "\neffort: " + наблюдение["усилие"] +
        "\nНативная задача: " + результат["задача"] + "\nВремя наблюдения: " + наблюдение["время"] +
        "\nSHA-256 строки: " + наблюдение["позиция"]["sha256"] + "\n" + конец)
    тело = основа.rstrip()[:-len(трейлер)]
    if тело.endswith(блок + "\n\n"):
        return основа
    # Не удаляем ни одного фрагмента исходного тела. Старый суффикс с иными
    # значениями требует исходную основу, чтобы не переинтерпретировать цитату.
    чтение._требовать(not тело.rstrip().endswith(конец), "коллизия суффикса; нужна исходная основа коммита")
    return тело + ("" if тело.endswith("\n\n") else "\n\n") + блок + "\n\n" + трейлер + "\n"


def сохранить_сообщение(назначение, текст):
    """Новый приватный файл с 0600 уже в момент создания, без окна chmod."""
    путь = _путь(назначение)
    чтение._требовать(not any(os.path.lexists(предок / ".git") for предок in путь.parents),
                     "сообщение коммита запрещено внутри Git")
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, "w", encoding="utf-8") as поток:
        поток.write(текст)
        поток.flush()
        os.fsync(поток.fileno())

from сообщения_задачи import _замок, _установить

КОРНЕВОЙ_ЯКОРЬ = обязательства.ГРАНИЦА_ЗАДАЧИ


def путь_принятия(задача):
    гит.требовать(str(uuid.UUID(задача)) == задача, "неканонический UUID исполнителя")
    return f"Планирование/задачи/{задача}/принятие-делегации.json"


def прочитать(корень, путь):
    файл = обработка.локальный_путь(корень, путь)
    return обработка.прочитать_файл(файл) if os.path.lexists(файл) else None


def проверить_историю(корень, задача, кандидат):
    история = гит.прочитать_историю(корень, путь_принятия(задача))
    версии = история["версии"]
    различные = {данные for данные in версии.values() if данные is not None}
    гит.требовать(len(различные) <= 1, "принятие переопределено в истории")
    for коммит, родители in история["родители"].items():
        for родитель in родители:
            гит.требовать(версии[родитель] is None or версии[коммит] == версии[родитель], "принятие удалено или изменено в истории")
    прежнее = версии[история["вершина"]]
    гит.требовать(прежнее is None or кандидат == прежнее, "долговечное принятие удалено или изменено")
    return история


def выбранное_поручение(корень, задача, выбор):
    обязательства.поля(выбор, {"координатор", "исполнитель", "коммит", "путь", "sha256"})
    гит.требовать(выбор["координатор"] == КОРНЕВОЙ_ЯКОРЬ["задача"] and выбор["исполнитель"] == задача,
                 "выбранные UUID не совпадают с независимым якорем и исполнителем")
    проверка = обязательства.ПроверкаОбязательств(корень, КОРНЕВОЙ_ЯКОРЬ, выбор["коммит"])
    остаток = проверка.остаток(None)
    _, данные = проверка.файл(выбор["коммит"], выбор["путь"])
    свидетельство = {"путь": выбор["путь"], "начало": 0, "конец": len(данные), "sha256": выбор["sha256"]}
    обработка.проверить_свидетельство(свидетельство)
    обработка.фрагмент(свидетельство, данные)
    поручение = обязательства.разобрать_байты(данные)
    обязательства.поля(поручение, {"схема", "координатор", "исполнитель", "работа", "поручение"})
    гит.требовать(поручение["схема"] == "fum.поручение-координатора.1" and
                 all(поручение[ключ] == выбор[ключ] for ключ in ("координатор", "исполнитель")), "неверная схема или адресация поручения")
    обязательства.поля(поручение["поручение"], {"действие", "ограничения"})
    обязательства.строка(поручение["поручение"]["действие"])
    ограничения = поручение["поручение"]["ограничения"]
    гит.требовать(isinstance(ограничения, list), "ограничения должны быть списком")
    for ограничение in ограничения:
        обязательства.строка(ограничение)
    гит.требовать(поручение["работа"] in остаток["доступные_работы"], "выбранная корневая работа недоступна в выбранном коммите")
    реестр = обязательства.разобрать_байты(проверка.история["версии"][выбор["коммит"]])
    работа = next(работа for работа in реестр["работы"] if работа["идентификатор"] == поручение["работа"])
    return поручение, работа["основание"]


def сверить_источник(корень, выбор):
    """DAG выбран по неизменяемому OID; повторно читается сам выбранный blob."""
    коммит = выбор["коммит"]
    данные = гит.прочитать_объекты(корень, [коммит], "commit")[коммит]
    деревья = [строка[5:].decode("ascii") for строка in данные.split(b"\n\n", 1)[0].split(b"\n") if строка.startswith(b"tree ")]
    гит.требовать(len(деревья) == 1, "повреждена граница выбранного коммита")
    состояние = гит.состояния_пути(корень, {коммит: деревья[0]}, выбор["путь"])[коммит]
    гит.требовать(состояние is not None, "выбранный источник исчез")
    данные = гит.прочитать_объекты(корень, [состояние[1]], "blob")[состояние[1]]
    обработка.фрагмент({"путь": выбор["путь"], "начало": 0, "конец": len(данные), "sha256": выбор["sha256"]}, данные)


def проверить_запись(корень, задача, данные, выбор, путь_плана, проверить_основание, входы):
    гит.требовать(выбор is not None, "для принятия отсутствует независимо выбранное поручение")
    поручение, основание = выбранное_поручение(корень, задача, выбор)
    запись = обязательства.разобрать_байты(данные)
    обязательства.поля(запись, {"схема", "выбранное_поручение", "корневая_работа", "корневое_основание", "план", "работа"})
    гит.требовать(запись["схема"] == "fum.принятие-делегации.1" and запись["выбранное_поручение"] == выбор,
                 "принятие не соответствует независимо выбранному поручению")
    гит.требовать(запись["корневая_работа"] == поручение["работа"] and запись["корневое_основание"] == основание,
                 "корневая работа или человеческое основание подменены")
    гит.точный_путь(запись["план"])
    гит.требовать(запись["план"] == путь_плана, "план принятия не совпадает с проверяемым планом")
    работа = запись["работа"]
    обязательства.поля(работа, {"идентификатор", "действие", "основание"})
    обязательства.строка(работа["идентификатор"])
    гит.требовать(работа["действие"] == поручение["поручение"]["действие"], "действие исполнителя подменено")
    проверить_основание(корень, работа["основание"], задача, {}, входы)
    return запись


def проверить(корень, задача, выбор, путь_плана, проверить_основание, повторные_сверки):
    путь = путь_принятия(задача)
    данные = прочитать(корень, путь)
    история = проверить_историю(корень, задача, данные)
    гит.требовать(выбор is None or данные is not None, "выбранное поручение требует сохранённого принятия")
    входы = {путь: данные}
    if данные is not None:
        запись = проверить_запись(корень, задача, данные, выбор, путь_плана, проверить_основание, входы)
        входы[путь_плана] = прочитать(корень, путь_плана)
        план = обязательства.разобрать_байты(входы[путь_плана])
        гит.требовать(план["схема"] == "fum.продолжение-задачи.1" and план["задача"] == задача, "приём поддерживает собственный план v1")
        работы = [работа for работа in план["работы"] if работа["идентификатор"] == запись["работа"]["идентификатор"]]
        гит.требовать(len(работы) == 1, "принятие не покрыто работой исполнителя: " + запись["работа"]["идентификатор"])
        гит.требовать(all(работы[0][ключ] == значение for ключ, значение in запись["работа"].items()), "связанная работа переопределена")

    def сверить():
        for имя, байты in входы.items():
            гит.требовать(прочитать(корень, имя) == байты, "вход принятия изменился перед решением")
        гит.требовать(гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip() == история["вершина"], "HEAD принятия изменился")
        if данные is not None:
            сверить_источник(корень, выбор)

    повторные_сверки.append(сверить)


def принять(корень, задача, выбор, запись, проверить_основание):
    """Создание один раз; повтор точных байтов идемпотентен, замена запрещена."""
    путь = путь_принятия(задача)
    данные = обязательства.канонические_байты(запись)
    каталог_гита = Path(os.fsdecode(гит.выполнить_чтение_репозитория(корень, "rev-parse", "--absolute-git-dir").strip()))
    with _замок(каталог_гита / "приём-делегации"):
        прежнее = прочитать(корень, путь)
        гит.требовать(прежнее is None or прежнее == данные, "принятие уже существует с другим содержимым")
        история = проверить_историю(корень, задача, прежнее)
        входы = {}
        проверить_запись(корень, задача, данные, выбор, запись["план"], проверить_основание, входы)
        for имя, байты in входы.items():
            гит.требовать(прочитать(корень, имя) == байты, "основание изменилось перед принятием")
        гит.требовать(прочитать(корень, путь) == прежнее and гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip() == история["вершина"], "граница принятия изменилась")
        файл = обработка.локальный_путь(корень, путь)
        каталог = корень
        for часть in файл.parent.relative_to(корень).parts:
            следующий = каталог / часть
            if not следующий.exists():
                следующий.mkdir()
            гит.требовать(следующий.is_dir() and not следующий.is_symlink(), "каталог принятия подменён")
            обработка.синхронизировать_каталог(каталог)
            каталог = следующий
        _установить(файл, данные)
    return запись


def выполнить():
    параметры = argparse.ArgumentParser(description=__doc__)
    параметры.add_argument("--корень-репозитория", type=Path, required=True)
    параметры.add_argument("--codex-thread-id", required=True)
    параметры.add_argument("--доверенное-поручение", required=True, help="JSON независимо выбранных коммита, пути, SHA и UUID")
    параметры.add_argument("--запись", type=Path, required=True, help="явный отдельный акт принятия JSON")
    аргументы = параметры.parse_args()
    try:
        описание = importlib.util.spec_from_file_location("допуск_приёма", Path(__file__).with_name("проверить-продолжение-задачи.py"))
        допуск = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(допуск)
        принять(аргументы.корень_репозитория.resolve(strict=True), аргументы.codex_thread_id,
                обязательства.разобрать_байты(аргументы.доверенное_поручение.encode()),
                обязательства.разобрать_байты(аргументы.запись.read_bytes()), допуск.проверить_основание)
        print("Принятие сохранено. Покрытие работой проверяет отдельный допуск.")
        return 0
    except (OSError, ValueError, RuntimeError, TypeError, KeyError) as ошибка:
        print("ошибка: " + str(ошибка), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(выполнить())

class ОшибкаОбязательств(ValueError):
    pass


def требовать(условие, сообщение):
    if not условие:
        raise ОшибкаОбязательств(сообщение)


def поля(значение, имена):
    требовать(isinstance(значение, dict) and set(значение) == set(имена), "неверный набор полей")


def строка(значение):
    требовать(isinstance(значение, str) and bool(значение.strip()), "ожидалась непустая строка")
    return значение


def уникальный_объект(пары):
    результат = {}
    for ключ, значение in пары:
        требовать(ключ not in результат, "повторный ключ JSON")
        результат[ключ] = значение
    return результат


def разобрать(байты):
    return json.loads(байты, object_pairs_hook=уникальный_объект)


def канонические_байты(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def имя_пути(имя):
    строка(имя)
    путь = PurePosixPath(имя)
    требовать(not путь.is_absolute() and путь.as_posix() == имя
              and all(часть not in ("", ".", "..", ".git") for часть in имя.split("/"))
              and not any(символ in имя for символ in ("\\", ":"))
              and not any(unicodedata.category(символ).startswith("C") for символ in имя),
              "неканонический локальный путь")
    требовать(путь.parts[0].casefold() != "proyekcii", "проекция не является доказательством")
    return имя


def имя_запроса(имя):
    имя_пути(имя)
    требовать(re.fullmatch(r"Журнал/\d{4}-\d{2}-\d{2}_\d{2}-\d{2}-\d{2}_MSK(?:_[^/]+)?/запрос\.md", имя),
              "ожидался канонический путь исходного запроса")
    return имя


def идентификатор_задачи(значение):
    требовать(isinstance(значение, str) and str(uuid.UUID(значение)) == значение,
              "неканонический UUID")
    return значение


def обычный_путь(корень, имя, каталог=False):
    имя_пути(имя)
    текущий = корень
    for часть in имя.split("/"):
        требовать(часть in {путь.name for путь in текущий.iterdir()}, "путь не найден с точным регистром")
        текущий = текущий / часть
        требовать(not текущий.is_symlink(), "символическая ссылка запрещена")
    требовать(текущий.is_dir() if каталог else текущий.is_file(), "неверный тип локального пути")
    return текущий


def текст_источника(байты, задача, разделы):
    содержание = разделы(байты.decode("utf-8"))
    тексты = содержание.get("Текст запроса", [])
    задачи = содержание.get("Идентификатор сеанса Codex", [])
    требовать(len(тексты) == len(задачи) == 1 and задачи[0].strip() == "Codex-Thread-ID: " + задача,
              "неоднозначный или чужой источник команды")
    return тексты[0]


def полные_команды(текст):
    """Только целый раздел либо последовательность дословных сообщений без обрамления."""
    сообщения = []
    строки = текст.splitlines()
    номер = 0
    остаток = []
    while номер < len(строки):
        открытие = re.fullmatch(r" {0,3}(`{3,}|~{3,})text\s*", строки[номер])
        if открытие:
            ограда = открытие[1]
            начало = номер + 1
            номер = начало
            while номер < len(строки) and re.fullmatch(re.escape(ограда[0]) + "{" + str(len(ограда)) + ",}", строки[номер].strip()) is None:
                номер += 1
            требовать(номер < len(строки), "незавершённая команда")
            сообщения.append("\n".join(строки[начало:номер]).strip())
        else:
            остаток.append(строки[номер])
        номер += 1
    if сообщения:
        return [] if any(строка.strip() for строка in остаток) else сообщения
    return [текст.strip()]


def проверить_остановку(корень, план, задача, разделы):
    требовать(isinstance(план, dict), "план должен быть объектом")
    основание = план.get("остановка")
    if основание is None:
        return False
    поля(основание, ("запрос", "цитата"))
    имя = имя_запроса(основание["запрос"])
    цитата = строка(основание["цитата"])
    допустимые = {"остановись", "остановить задачу", "останови задачу", "прекрати работу", "stop", "stop the task", "ostanovisj", "ostanovis'"}
    требовать(цитата.strip().casefold().rstrip(".! ") in допустимые,
              "цитата не является поддержанной однозначной командой остановки")
    текст = текст_источника(обычный_путь(корень, имя).read_bytes(), задача, разделы)
    требовать(цитата.strip() in полные_команды(текст), "остановка должна быть полным первичным сообщением")
    return True


class ЧтениеГит:
    def __init__(это, корень):
        это.корень = корень
        это.объекты = {}
        это.деревья = {}
        это.истории = {}
        это.окружение = {ключ: значение for ключ, значение in os.environ.items() if not ключ.startswith("GIT_")}
        это.окружение["GIT_OPTIONAL_LOCKS"] = "0"

    def выполнить(это, *аргументы, вход=None):
        ответ = subprocess.run(["git", "--no-replace-objects", "--literal-pathspecs", "-c", "core.fsmonitor=false",
                                "-C", str(это.корень), *аргументы], input=вход, capture_output=True,
                               env=это.окружение, timeout=45)
        требовать(ответ.returncode == 0, "не удалось прочитать реальные объекты Git: " + аргументы[0])
        return ответ.stdout

    def прочитать_объекты(это, идентификаторы):
        новые = sorted(set(идентификаторы) - это.объекты.keys())
        if новые:
            вывод = это.выполнить("cat-file", "--batch", вход=("\n".join(новые) + "\n").encode())
            смещение = 0
            for ожидаемый in новые:
                конец = вывод.index(b"\n", смещение)
                описание = вывод[смещение:конец].split()
                требовать(len(описание) == 3 and описание[0].decode() == ожидаемый,
                          "объект Git отсутствует или подменён")
                размер = int(описание[2])
                это.объекты[ожидаемый] = (описание[1].decode(), вывод[конец + 1:конец + 1 + размер])
                смещение = конец + размер + 2
            требовать(смещение == len(вывод), "лишние байты пакетного ответа Git")
        return {идентификатор: это.объекты[идентификатор] for идентификатор in идентификаторы}

    def дерево(это, коммит, область=None):
        ключ = (коммит, область)
        if ключ not in это.деревья:
            аргументы = ["ls-tree", "-r", "-z", коммит]
            if область:
                аргументы.extend(["--", область])
            дерево = {}
            for запись in это.выполнить(*аргументы).split(b"\0"):
                if запись:
                    описание, имя = запись.split(b"\t", 1)
                    режим, тип, объект = описание.decode().split()
                    дерево[имя.decode("utf-8")] = (режим, тип, объект)
            это.деревья[ключ] = дерево
        return это.деревья[ключ]

    def файл(это, коммит, имя):
        запись = это.дерево(коммит, имя).get(имя)
        if запись is None:
            return None
        требовать(запись[0] in ("100644", "100755") and запись[1] == "blob", "Git-путь не является обычным файлом")
        return это.прочитать_объекты([запись[2]])[запись[2]][1]

    def версии_пути(это, коммиты, имя):
        записи = это.записи_истории(коммиты, имя)
        версии = {коммит: запись[2] if запись is not None else None for коммит, запись in записи.items()}
        это.прочитать_объекты([значение for значение in версии.values() if значение is not None])
        return версии

    def записи_истории(это, коммиты, имя):
        """Пакетно разрешает родительские деревья, сохраняя режимы и полный DAG."""
        ключ = (tuple(коммиты), имя)
        if ключ in это.истории:
            return это.истории[ключ]
        путь = PurePosixPath(имя)
        родитель = путь.parent.as_posix()
        запросы = [коммит + ("^{tree}" if родитель == "." else ":" + родитель) for коммит in коммиты]
        строки = это.выполнить("cat-file", "--batch-check", вход=("\n".join(запросы) + "\n").encode()).splitlines()
        требовать(len(строки) == len(запросы), "неполный ответ об истории пути")
        записи = {}
        for коммит, запрос, строка_ответа in zip(коммиты, запросы, строки):
            if строка_ответа == (запрос + " missing").encode():
                записи[коммит] = None
            else:
                объект, тип, _ = строка_ответа.decode().split()
                требовать(тип == "tree", "предок исторического пути не является деревом")
                дерево = это.дерево(объект, путь.name)
                запись = дерево.get(путь.name)
                требовать(not дерево or запись is not None, "исторический файл заменён каталогом")
                требовать(запись is None or запись[0] in ("100644", "100755") and запись[1] == "blob",
                          "исторический путь не является обычным файлом")
                записи[коммит] = запись
        это.истории[ключ] = записи
        return записи


class ПроверкаОбязательств:
    def __init__(это, корень, задача, разделы, метки):
        это.корень = корень
        это.задача = идентификатор_задачи(задача)
        это.разделы = разделы
        это.метки = метки
        это.гит = ЧтениеГит(корень)
        это.вершина = это.гит.выполнить("rev-parse", "--verify", "HEAD").decode().strip()
        требовать(это.гит.выполнить("rev-parse", "--is-shallow-repository").strip() == b"false", "неполная Git-история")
        прививки = Path(os.fsdecode(это.гит.выполнить("rev-parse", "--git-path", "info/grafts").strip()))
        if not прививки.is_absolute():
            прививки = корень / прививки
        требовать(not прививки.exists(), "подменённая история grafts не допускается")
        граф = это.гит.выполнить("rev-list", "--topo-order", "--parents", это.вершина).decode().splitlines()
        это.родители = {части[0]: части[1:] for линия in граф if (части := линия.split())}
        это.путь_реестра = f"Планирование/задачи/{задача}/обязательства.json"
        это.рабочие_байты = {}
        это.рабочие_каталоги = {}
        это.источники = {}
        это.проверенные_истории = {}
        это.отчёты = None

    @contextmanager
    def стадия(это, метка):
        начало = time.perf_counter_ns()
        исход = "ошибка"
        try:
            yield
            исход = "успешно"
        finally:
            это.метки.append({"метка": метка, "длительность_нс": time.perf_counter_ns() - начало, "исход": исход, "родитель": "проверка обязательств"})

    def рабочий_файл(это, имя):
        if имя not in это.рабочие_байты:
            путь = обычный_путь(это.корень, имя)
            это.рабочие_байты[имя] = (путь.read_bytes(), stat.S_IMODE(путь.stat().st_mode))
        return это.рабочие_байты[имя][0]

    def источник(это, коммит, имя):
        имя_запроса(имя)
        ключ = (коммит, имя)
        if ключ not in это.источники:
            if коммит is None:
                байты = это.рабочий_файл(имя)
            else:
                требовать(коммит in это.родители, "источник не является достижимым коммитом")
                байты = это.гит.файл(коммит, имя)
                требовать(байты is not None, "исходная команда отсутствует в коммите")
            это.источники[ключ] = текст_источника(байты, это.задача, это.разделы)
        return это.источники[ключ]

    def основание(это, основание, историческое=False):
        поля(основание, ("коммит", "запрос", "цитата") if историческое else ("запрос", "цитата"))
        коммит = основание.get("коммит")
        if историческое:
            требовать(isinstance(коммит, str) and re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", коммит), "неполный OID основания")
        требовать(строка(основание["цитата"]) in это.источник(коммит, основание["запрос"]), "цитата отсутствует в своём источнике")

    def структура_реестра(это, реестр):
        поля(реестр, ("схема", "задача", "исходный_коммит", "план_этапа", "обязательства"))
        требовать(реестр["схема"] == "fum.обязательства-задачи.2" and реестр["задача"] == это.задача, "неверная схема или задача реестра")
        требовать(реестр["исходный_коммит"] in это.родители, "исходный коммит недостижим")
        имя_пути(реестр["план_этапа"])
        требовать(isinstance(реестр["обязательства"], list) and реестр["обязательства"], "пустой реестр не доказывает завершение")
        результат = {}
        for обязательство in реестр["обязательства"]:
            поля(обязательство, ("идентификатор", "родитель", "основание", "вид_результата", "карточка", "приёмки"))
            имя = строка(обязательство["идентификатор"])
            требовать(имя not in результат, "повтор идентификатора обязательства")
            требовать(обязательство["вид_результата"] in ("реализация", "документ"), "неизвестный вид результата")
            карточка = обязательство["карточка"]
            требовать(карточка is None or isinstance(карточка, str) and re.fullmatch(r"FUM-STEP-\d{4}", карточка), "неверный ID карточки")
            это.основание(обязательство["основание"], историческое=True)
            требовать(isinstance(обязательство["приёмки"], list), "приёмки должны быть списком")
            известные = set()
            for приёмка in обязательство["приёмки"]:
                поля(приёмка, ("запрос", "запуск", "результаты"))
                имя_запроса(приёмка["запрос"])
                идентификатор_задачи(приёмка["запуск"])
                ключ = (приёмка["запрос"], приёмка["запуск"])
                требовать(ключ not in известные, "повтор приёмки")
                известные.add(ключ)
                требовать(isinstance(приёмка["результаты"], list) and приёмка["результаты"], "нет результатов приёмки")
                пути = set()
                for запись in приёмка["результаты"]:
                    поля(запись, ("путь", "sha256"))
                    путь = имя_пути(запись["путь"])
                    приведённый = unicodedata.normalize("NFC", путь).casefold()
                    требовать(приведённый not in пути, "повтор или коллизия результата")
                    пути.add(приведённый)
                    требовать(isinstance(запись["sha256"], str) and re.fullmatch(r"[0-9a-f]{64}", запись["sha256"]), "неверный SHA-256 результата")
            результат[имя] = обязательство
        for имя in результат:
            посещённые = set()
            текущий = имя
            while текущий is not None:
                требовать(isinstance(текущий, str) and текущий in результат and текущий not in посещённые, "неизвестный родитель или цикл обязательств")
                посещённые.add(текущий)
                текущий = результат[текущий]["родитель"]
        return результат

    def история_реестра(это, реестр):
        обязательства = это.структура_реестра(реестр)
        версии = это.гит.версии_пути(list(это.родители), это.путь_реестра)
        разобранные = {}
        определения = {}
        for объект in set(версии.values()) - {None}:
            прежний = разобрать(это.гит.объекты[объект][1])
            требовать(прежний["исходный_коммит"] == реестр["исходный_коммит"], "новый генезис реестра запрещён")
            разобранные[объект] = это.структура_реестра(прежний)
            for имя, обязательство in разобранные[объект].items():
                неизменное = {ключ: значение for ключ, значение in обязательство.items() if ключ != "приёмки"}
                требовать(имя not in определения or определения[имя] == неизменное, "определение обязательства изменялось в достижимой истории")
                определения[имя] = неизменное
        проверенные_предки = set()

        def предшествует(предок, потомок):
            связь = (предок, потомок)
            if связь not in проверенные_предки:
                это.гит.выполнить("merge-base", "--is-ancestor", предок, потомок)
                проверенные_предки.add(связь)

        for коммит, объект in версии.items():
            текущие = разобранные.get(объект, {})
            for родитель in это.родители[коммит]:
                требовать(родитель in версии, "DAG истории неполон")
                прежние = разобранные.get(версии[родитель], {})
                это.не_ослаблено(прежние, текущие)
            if объект is not None:
                if not any(версии[родитель] is not None for родитель in это.родители[коммит]):
                    предшествует(реестр["исходный_коммит"], коммит)
                for имя, обязательство in текущие.items():
                    if not any(имя in разобранные.get(версии[родитель], {}) for родитель in это.родители[коммит]):
                        предшествует(обязательство["основание"]["коммит"], коммит)
        это.не_ослаблено({имя: dict(определение, приёмки=[]) for имя, определение in определения.items()}, обязательства)
        это.не_ослаблено(разобранные.get(версии[это.вершина], {}), обязательства)
        база = реестр["исходный_коммит"]
        предки_базы = это.гит.выполнить("rev-list", база).decode().splitlines()
        требовать(all(версии.get(коммит) is None for коммит in предки_базы), "исходный коммит должен предшествовать первому реестру")
        это.версии_реестра = версии
        это.реестры = разобранные
        return обязательства

    @staticmethod
    def не_ослаблено(прежние, текущие):
        for имя, прежнее in прежние.items():
            требовать(имя in текущие, "обязательство удалено из реестра или merge")
            текущее = текущие[имя]
            требовать(all(текущее[ключ] == значение for ключ, значение in прежнее.items() if ключ != "приёмки"), "неизменяемое определение обязательства ослаблено")
            байты = {канонические_байты(приёмка) for приёмка in текущее["приёмки"]}
            требовать(all(канонические_байты(приёмка) in байты for приёмка in прежнее["приёмки"]), "прежняя приёмка удалена или изменена")

    def карточки(это):
        результат = {}
        дерево = это.гит.дерево(это.вершина, "Планирование/карточки-шагов")
        это.гит.прочитать_объекты([запись[2] for имя, запись in дерево.items() if имя.endswith(".md") and not имя.endswith("/README.md")])
        for имя, запись in дерево.items():
            if not имя.endswith(".md") or имя == "Планирование/карточки-шагов/README.md":
                continue
            требовать(имя.count("/") == 2 and запись[0] in ("100644", "100755"), "небезопасный путь карточки")
            текст = это.гит.объекты[запись[2]][1].decode("utf-8")
            совпадение = re.match(r"\A\+\+\+\n(.*?)\n\+\+\+\n", текст, re.S)
            требовать(совпадение is not None, "нет TOML-контракта карточки")
            данные = tomllib.loads(совпадение[1])
            поля(данные, ("schema_version", "card_id", "status"))
            идентификатор = данные["card_id"]
            статусы = {"active": "🟡", "completed": "✅", "absorbed": "🧩", "withdrawn": "🗑️"}
            требовать(type(данные["schema_version"]) is int and данные["schema_version"] == 1
                      and данные["status"] in статусы and isinstance(идентификатор, str)
                      and re.fullmatch(r"FUM-STEP-\d{4}", идентификатор)
                      and идентификатор not in результат, "некорректная или повторная карточка")
            требовать(Path(имя).name.startswith(статусы[данные["status"]] + "-" + идентификатор + "-"), "имя карточки не совпадает с TOML")
            результат[идентификатор] = (данные["status"], имя)
        return результат


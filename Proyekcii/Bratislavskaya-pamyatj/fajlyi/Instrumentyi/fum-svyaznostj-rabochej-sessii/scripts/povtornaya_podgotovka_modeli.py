"""Связать свежую читающую сверку с неизменной сохранённой историей модели."""

import hashlib
import json
from pathlib import Path


def наблюдать_сохранённую(параметры, прочитать, наблюдать):
    история = Path(параметры['корень']) / параметры['история_модели']
    курсор = Path(параметры['кэш_модели'])
    исходная = прочитать(история)
    приватный = прочитать(курсор, приватный=True)
    сохранённая = json.loads(исходная)
    данные_курсора = json.loads(приватный)['данные']
    if данные_курсора['подготовлено'] or данные_курсора['история'] != сохранённая:
        raise ValueError('для повторной подготовки нужна согласованная сохранённая история и курсор')
    # Импортёр проверяет подпись курсора, источник, прежний префикс и новый хвост.
    свежая = наблюдать(параметры, без_записи=True)
    if (свежая['новых_наблюдений'] != 0 or
            свежая['число_наблюдений'] != сохранённая['число_наблюдений'] or
            свежая['последнее'] != сохранённая['последнее']):
        raise ValueError('наблюдения модели изменились; нужна обычная подготовка до проверок')
    if прочитать(история) != исходная or прочитать(курсор, приватный=True) != приватный:
        raise ValueError('история или курсор изменились при повторной подготовке')
    модель = {**свежая, 'история_sha256': hashlib.sha256(исходная).hexdigest()}
    return модель, свежая, исходная

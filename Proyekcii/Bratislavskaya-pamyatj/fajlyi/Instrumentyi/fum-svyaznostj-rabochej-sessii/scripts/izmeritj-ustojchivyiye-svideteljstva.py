"""Открытый сравнительный профиль; счёт операций задан явно, время измерено."""
import json
import sys
import time
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tests"))
import test_устойчивые_свидетельства as фикстура
import устойчивые_свидетельства as модуль


def измерить(автоматически):
    проверка = фикстура.ПроверкаСвидетельств()
    проверка.setUp()
    try:
        проверка.добавить("Сделай.\n", 2)
        решения = проверка.решения()
        счёт = 0
        настоящий = модуль.читатель.прочитать_сообщения
        def читать(*аргументы, **параметры):
            nonlocal счёт
            счёт += 1
            return настоящий(*аргументы, **параметры)
        начало = time.perf_counter_ns()
        with mock.patch.object(модуль.читатель, "прочитать_сообщения", side_effect=читать):
            if автоматически:
                план = проверка.план(решения)
                итог = проверка.применить(план)
                assert итог["применено"]
            else:
                снимок = проверка.остаток()
                история = снимок["история_sha256"]
                for номер, решение in enumerate(решения):
                    запись = {ключ: решение[ключ] for ключ in ("экземпляр", "решение", "актуальность", "поздние")}
                    запись["контекст"] = снимок["контекст"]
                    for имя in ("команда", "ответ", "основание"):
                        if имя == "команда":
                            байты = модуль.читатель._байты(снимок["сообщения"][номер]["содержимое"])
                        else:
                            байты = модуль.обработка.фрагмент(решение[имя], (проверка.корень / решение[имя]["путь"]).read_bytes())
                        путь = f"Журнал/пример/материалы/ручной/{номер}/{имя}.txt"
                        файл = проверка.корень / путь
                        файл.parent.mkdir(parents=True, exist_ok=True)
                        файл.write_bytes(байты)
                        запись[имя] = модуль.свидетельство(путь, байты)
                    запись["команда"]["формат"] = "части-json"
                    итог = модуль.обработка.сохранить_обработку(проверка.источник, фикстура.основа.ЗАДАЧА,
                        корень_репозитория=проверка.корень, кэш=проверка.кэш, запись=запись, ожидаемая_история=история)
                    история = итог["история_sha256"]
        длительность = time.perf_counter_ns() - начало
        assert not проверка.остаток()["остаток"]
        return {"длительность_наносекунды": длительность, "вызовы_читателя": счёт,
                "экземпляры": 2, "разбор_завершён": True, "обязательства_завершены": False}
    finally:
        проверка.doCleanups()



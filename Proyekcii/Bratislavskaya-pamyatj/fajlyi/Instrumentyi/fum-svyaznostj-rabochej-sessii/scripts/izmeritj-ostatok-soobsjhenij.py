"""Профиль полного остатка: открытый JSONL 70 МиБ, Git и одно сохранённое решение."""
import argparse
import hashlib
import json
import os
import platform
import resource
import statistics
import subprocess
import tempfile
import time
from pathlib import Path

import обработка_сообщений as обработка


ЗАДАЧА = "00000000-0000-0000-0000-000000000177"


def строка(значение):
    return (json.dumps(значение, ensure_ascii=False, separators=(",", ":")) + "\n").encode()


def сообщение(номер, текст):
    return строка({"type": "response_item", "payload": {"type": "message", "role": "user", "id": f"msg_{номер}",
        "content": [{"type": "input_text", "text": текст}], "internal_chat_message_metadata_passthrough": {"content_item_kinds": ["user.text"]}}})


def измерить(повторов, выход, без_кэша_границ=False, без_записи=False):
    результаты = []
    with tempfile.TemporaryDirectory() as каталог:
        временный = Path(каталог)
        корень = временный / "проект"
        корень.mkdir()
        def гит(*аргументы):
            subprocess.run(["git", "-c", f"core.hooksPath={os.devnull}", "-c", "user.name=Открытая фикстура", "-c", "user.email=fixture@example.invalid", *аргументы], cwd=корень, check=True, capture_output=True)
        гит("init", "-q")
        (корень / "Журнал/пример").mkdir(parents=True)
        запрос = "Журнал/пример/запрос.md"
        отчёт = "Журнал/пример/отчёт.md"
        (корень / запрос).write_text("Codex-Thread-ID: " + ЗАДАЧА + "\nПовтори.\n")
        (корень / отчёт).write_text("Повтор принят в работу.\nСтарое поручение сохраняется до проверки.\n")
        гит("add", ".")
        гит("commit", "-qm", "Сохранить открытую фикстуру")
        источник = временный / "диалог.jsonl"
        блок = строка({"type": "event_msg", "payload": {"type": "fixture", "text": "я" * 2048}})
        with источник.open("wb") as поток:
            поток.write(строка({"type": "session_meta", "payload": {"id": ЗАДАЧА}}))
            поток.write(сообщение(1, "Старое поручение.\n"))
            for _ in range(70 * 1024 * 1024 // len(блок) + 1):
                поток.write(блок)
            поток.write(сообщение(2, "Повтори.\n") + сообщение(3, "Повтори.\n") + сообщение(4, "Приоритет изменён.\n"))
        вход = источник.read_bytes()
        кэш_подготовки = временный / "подготовка.json"
        снимок = обработка.получить_остаток(источник, ЗАДАЧА, корень_репозитория=корень, кэш=кэш_подготовки)
        def свидетельство(путь, текст):
            байты = (корень / путь).read_bytes()
            часть = текст.encode()
            начало = байты.index(часть)
            return {"путь": путь, "начало": начало, "конец": начало + len(часть), "sha256": hashlib.sha256(часть).hexdigest()}
        предложение = {"экземпляр": снимок["сообщения"][1]["экземпляр"], "контекст": снимок["контекст"], "решение": "работа", "актуальность": "актуально", "поздние": [],
            "команда": {**свидетельство(запрос, "Повтори.\n"), "формат": "текст"},
            "ответ": свидетельство(отчёт, "Повтор принят в работу.\n"), "основание": свидетельство(отчёт, "Старое поручение сохраняется до проверки.\n")}
        обработка.сохранить_обработку(источник, ЗАДАЧА, корень_репозитория=корень, кэш=кэш_подготовки, запись=предложение, ожидаемая_история=снимок["история_sha256"])
        гит("add", ".")
        гит("commit", "-qm", "Сохранить одно подтверждение")
        история = (корень / обработка.путь_истории(ЗАДАЧА)).read_bytes()
        for повтор in range(повторов):
            источник.write_bytes(вход)
            кэш = временный / f"измерение-{повтор}.json"
            for стадия in ("первичное", "повторное", "с_хвостом"):
                if стадия == "с_хвостом":
                    with источник.open("ab") as поток:
                        поток.write(сообщение(5, "Позднее уточнение сохраняет оригиналы.\n"))
                входные_байты = источник.read_bytes()
                начало_процессора = time.process_time_ns()
                начало = time.perf_counter_ns()
                результат = обработка.получить_остаток(источник, ЗАДАЧА, корень_репозитория=корень, кэш=кэш, кэшировать_границы=not без_кэша_границ, без_записи=без_записи)
                длительность = time.perf_counter_ns() - начало
                процессор = time.process_time_ns() - начало_процессора
                assert len(результат["сообщения"]) == (5 if стадия == "с_хвостом" else 4)
                assert len(результат["остаток"]) == (5 if стадия == "с_хвостом" else 3)
                assert результат["остаток"][0]["экземпляр"] == снимок["сообщения"][0]["экземпляр"]
                assert not результат["завершение_задачи_доказано"]
                результаты.append({"повтор": повтор + 1, "стадия": стадия, "вход_sha256": hashlib.sha256(входные_байты).hexdigest(), "вход_байтов": len(входные_байты),
                    "длительность_наносекунды": длительность, "процессор_наносекунды": процессор, "профиль": результат["профиль"],
                    "максимальная_резидентная_память": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss})
        файлы = [Path(__file__), Path(обработка.__file__), Path(обработка.читатель.__file__), Path(обработка.читатель._ПУТЬ_КЛАССИФИКАТОРА), Path(обработка.гит.__file__)]
        профиль = {"схема": "fum.профиль-остатка-сообщений.1", "python": platform.python_version(), "платформа": platform.system(), "кэш_границ": not без_кэша_границ,
            "без_записи": без_записи,
            "код": {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in файлы}, "история_sha256": hashlib.sha256(история).hexdigest(),
            "граница": "Подготовка фикстуры, сохранение решения и Git-коммиты исключены; чтение JSONL, Git DAG и свидетельств включены; кэш ФС не сбрасывается; память — накопленный максимум процесса; процессор не включает дочерние Git-процессы.",
            "единица_памяти": "байт" if platform.system() == "Darwin" else "КиБ", "запуски": результаты,
            "медианы_наносекунды": {стадия: statistics.median(э["длительность_наносекунды"] for э in результаты if э["стадия"] == стадия) for стадия in ("первичное", "повторное", "с_хвостом")}}
        выход.write_text(json.dumps(профиль, ensure_ascii=False, indent=2) + "\n")
        print(json.dumps(профиль["медианы_наносекунды"], ensure_ascii=False))


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--повторов", type=int, default=3)
    разбор.add_argument("--выход", type=Path, required=True)
    разбор.add_argument("--без-кэша-границ", action="store_true")
    разбор.add_argument("--без-записи", action="store_true")
    параметры = разбор.parse_args()
    if not 1 <= параметры.повторов <= 21:
        разбор.error("число повторов должно быть от 1 до 21")
    измерить(параметры.повторов, параметры.выход, параметры.без_кэша_границ, параметры.без_записи)

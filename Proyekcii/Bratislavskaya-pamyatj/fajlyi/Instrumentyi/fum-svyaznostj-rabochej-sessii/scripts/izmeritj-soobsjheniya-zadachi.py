"""Открытый воспроизводимый профиль: старый пропуск в JSONL больше 64 МиБ."""
import argparse
import hashlib
import importlib.util
import json
import platform
import resource
import statistics
import tempfile
import time
from pathlib import Path


ЗАДАЧА = "00000000-0000-0000-0000-000000000177"


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, separators=(",", ":")) + "\n").encode()


def команда(номер, текст):
    return байты({"type": "response_item", "payload": {"type": "message", "role": "user", "id": f"msg_{номер}",
        "content": [{"type": "input_text", "text": текст}],
        "internal_chat_message_metadata_passthrough": {"content_item_kinds": ["user.text"]}}})


def измерить(повторов, выход, полное_чтение):
    путь = Path(__file__).with_name("сообщения_задачи.py")
    спецификация = importlib.util.spec_from_file_location("измеряемые_сообщения", путь)
    модуль = importlib.util.module_from_spec(спецификация)
    спецификация.loader.exec_module(модуль)
    результаты = []
    with tempfile.TemporaryDirectory() as каталог:
        временный = Path(каталог)
        корень = временный / "проект"
        корень.mkdir()
        источник = временный / "диалог.jsonl"
        строка_события = байты({"type": "event_msg", "payload": {"type": "fixture", "text": "я" * 2048}})
        заголовок = байты({"type": "session_meta", "payload": {"id": ЗАДАЧА}})
        начало = команда(1, "Сначала сохрани старое поручение.\n") + команда(2, "Повтори.\n")
        конец = команда(3, "Повтори.\n") + команда(4, "Приоритет изменён: сначала разбор.\n")
        количество = (70 * 1024 * 1024) // len(строка_события) + 1
        for повтор in range(повторов):
            хэширование = hashlib.sha256()
            with источник.open("wb") as поток:
                for часть in (заголовок, начало):
                    поток.write(часть)
                    хэширование.update(часть)
                for _ in range(количество):
                    поток.write(строка_события)
                    хэширование.update(строка_события)
                поток.write(конец)
                хэширование.update(конец)
            размер = источник.stat().st_size
            кэш = временный / f"кэш-{повтор}.json"
            ожидаемые = None
            for стадия in ("первичное", "повторное", "с_хвостом"):
                if стадия == "с_хвостом":
                    хвост = команда(5, "Позднее уточнение не отменяет сохранения оригиналов.\n")
                    with источник.open("ab") as поток:
                        поток.write(хвост)
                    текущий_хэш = хэширование.copy()
                    текущий_хэш.update(хвост)
                else:
                    текущий_хэш = хэширование
                начало_процессора = time.process_time_ns()
                начало_времени = time.perf_counter_ns()
                снимок = модуль.прочитать_сообщения(источник, ЗАДАЧА, корень_репозитория=корень, кэш=кэш, перепроверить=полное_чтение)
                длительность = time.perf_counter_ns() - начало_времени
                процессор = time.process_time_ns() - начало_процессора
                экземпляры = [сообщение["экземпляр"] for сообщение in снимок["сообщения"]]
                assert снимок["полнота_подтверждена"] and len(экземпляры) == (5 if стадия == "с_хвостом" else 4)
                if ожидаемые is None:
                    ожидаемые = экземпляры
                else:
                    assert экземпляры[:4] == ожидаемые
                результаты.append({"повтор": повтор + 1, "стадия": стадия,
                    "вход_sha256": текущий_хэш.hexdigest(), "вход_байтов": источник.stat().st_size,
                    "длительность_наносекунды": длительность, "процессор_наносекунды": процессор,
                    "профиль_читателя": снимок["профиль"],
                    "максимальная_резидентная_память": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss})
        результат = {"схема": "fum.профиль-сообщений.1", "код_sha256": hashlib.sha256(путь.read_bytes()).hexdigest(),
            "реализация_sha256": модуль._РЕАЛИЗАЦИЯ, "полное_чтение": полное_чтение,
            "сценарий_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "вход_sha256": хэширование.hexdigest(), "вход_байтов": размер,
            "python": platform.python_version(), "платформа": platform.system(),
            "единица_памяти": "байт" if platform.system() == "Darwin" else "КиБ",
            "граница": "Создание фикстуры исключено; память — накопленный максимум процесса; кэш ФС не сбрасывается; исходники и результат одинаковы во всех повторах.",
            "запуски": результаты,
            "медианы_наносекунды": {стадия: statistics.median(запись["длительность_наносекунды"] for запись in результаты if запись["стадия"] == стадия) for стадия in ("первичное", "повторное", "с_хвостом")}}
        выход.write_bytes((json.dumps(результат, ensure_ascii=False, indent=2) + "\n").encode())
        print(json.dumps({"вход_байтов": размер, "медианы_наносекунды": результат["медианы_наносекунды"]}, ensure_ascii=False))


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--повторов", type=int, default=3)
    разбор.add_argument("--выход", type=Path, required=True)
    разбор.add_argument("--полное-чтение", action="store_true", help="Базовый режим: повторно читать и разбирать все строки")
    параметры = разбор.parse_args()
    if not 1 <= параметры.повторов <= 21:
        разбор.error("число повторов должно быть от 1 до 21")
    измерить(параметры.повторов, параметры.выход, параметры.полное_чтение)

"""Явное описание → неизменяемые материалы → штатная обработка по порядку.

Доверенный процесс и единственный писатель: описание и его ожидаемый хэш
передаются раздельно. Хэш не удостоверяет автора или допустимость публикации.
"""
from __future__ import annotations

import copy
import os
from pathlib import Path

import обработка_сообщений as обработка
import сообщения_задачи as читатель


def допуск(корень):
    return {"корень": str(корень),
            "HEAD": обработка.гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip(),
            "ref": обработка.гит.выполнить_чтение_репозитория(корень, "symbolic-ref", "HEAD").decode().strip()}


def свидетельство(путь, байты):
    return {"путь": путь, "начало": 0, "конец": len(байты), "sha256": обработка.хэш(байты)}


def построить(снимок, решения, каталог, *, сохранённые=False):
    обработка.требовать(type(решения) is list and решения, "нужен явный непустой выбор решений")
    обработка.гит.точный_путь(каталог)
    части = Path(каталог).parts
    обработка.требовать(len(части) >= 4 and части[0] == "Журнал" and части[2] == "материалы", "материалы должны принадлежать одному запросу")
    файлы, записи, выбранные = [], [], set()
    for решение in решения:
        обработка.объект(решение, {"экземпляр", "решение", "актуальность", "поздние", "ответ", "основание", "допустимые_части_sha256"})
        экземпляр = решение["экземпляр"]
        обработка.отпечаток(экземпляр)
        обработка.требовать(экземпляр not in выбранные, "повторный выбор экземпляра")
        выбранные.add(экземпляр)
        запись = {имя: copy.deepcopy(решение[имя]) for имя in ("экземпляр", "решение", "актуальность", "поздние")}
        запись["контекст"] = обработка.контекст_снимка(снимок)
        исходное = обработка.сверить_экземпляры(запись, снимок)
        байты = читатель._байты(исходное["содержимое"])
        обработка.требовать(решение["допустимые_части_sha256"] == обработка.хэш(байты), "нет явного допуска полных исходных частей к публикации")
        поколение = обработка.хэш(читатель._байты(решение))
        содержимое = {"команда": байты}
        for имя in ("ответ", "основание"):
            обработка.проверить_свидетельство(решение[имя])
            устойчивый = обработка.локальный_путь(Path(снимок["корень"]), f"{каталог}/{экземпляр}/{поколение}/{имя}.txt")
            if сохранённые and устойчивый.exists():
                байты_части = обработка.прочитать_файл(устойчивый)
                обработка.требовать(обработка.хэш(байты_части) == решение[имя]["sha256"] and len(байты_части) == решение[имя]["конец"] - решение[имя]["начало"], "устойчивый материал не совпал с исходным свидетельством")
                содержимое[имя] = байты_части
            else:
                содержимое[имя] = обработка.фрагмент(решение[имя], обработка.прочитать_файл(обработка.локальный_путь(Path(снимок["корень"]), решение[имя]["путь"])))
        # Каждое решение имеет отдельный набор; прежние файлы не меняются.
        for имя, байты in содержимое.items():
            путь = f"{каталог}/{экземпляр}/{поколение}/{имя}." + ("json" if имя == "команда" else "txt")
            файлы.append({"путь": путь, "текст": байты.decode("utf-8"), "sha256": обработка.хэш(байты)})
            запись[имя] = свидетельство(путь, байты)
        запись["команда"]["формат"] = "части-json"
        обработка.проверить_предложение(запись)
        записи.append(запись)
    return файлы, записи


def подготовить(источник, задача, *, корень_репозитория, каталог, решения):
    корень = Path(корень_репозитория).resolve(strict=True)
    начало = допуск(корень)
    снимок, история, _, _, _ = обработка.загрузить(источник, задача, корень, None, False, без_записи=True)
    обработка.требовать(снимок["полнота_подтверждена"], "неполный источник")
    снимок["корень"] = str(корень)
    файлы, записи = построить(снимок, решения, каталог)
    план = {"схема": "fum.устойчивые-свидетельства.1", "оператор": "сохранить-устойчивые-свидетельства",
            "задача": задача, "допуск": начало, "источник": снимок["источник"],
            "контекст": обработка.контекст_снимка(снимок), "история": история.decode("utf-8"),
            "история_sha256": обработка.хэш(история), "каталог": каталог, "решения": copy.deepcopy(решения),
            "файлы": файлы, "записи": записи,
            "порядок": ["проверить-входы", "сохранить-материалы", "сохранить-обработку-последовательно"],
            "повтор": "тот-же-план-через-штатную-идемпотентность", "завершение_задачи_доказано": False}
    проверить(источник, задача, корень, план, обработка.хэш(читатель._байты(план)))
    return план


def проверить(источник, задача, корень, план, ожидаемый_хэш):
    обработка.отпечаток(ожидаемый_хэш)
    обработка.требовать(обработка.хэш(читатель._байты(план)) == ожидаемый_хэш, "план изменён")
    обработка.объект(план, {"схема", "оператор", "задача", "допуск", "источник", "контекст", "история", "история_sha256", "каталог", "решения", "файлы", "записи", "порядок", "повтор", "завершение_задачи_доказано"})
    обработка.требовать(план["схема"] == "fum.устойчивые-свидетельства.1" and план["оператор"] == "сохранить-устойчивые-свидетельства" and план["задача"] == задача, "неверный оператор или задача")
    обработка.требовать(план["порядок"] == ["проверить-входы", "сохранить-материалы", "сохранить-обработку-последовательно"] and план["повтор"] == "тот-же-план-через-штатную-идемпотентность" and план["завершение_задачи_доказано"] is False, "неподдержанное поведение оператора")
    обработка.требовать(допуск(корень) == план["допуск"], "изменился допуск дерева")
    снимок, сырые, события, _, _ = обработка.загрузить(источник, задача, корень, None, False, без_записи=True)
    обработка.требовать(снимок["полнота_подтверждена"] and снимок["источник"] == план["источник"], "источник неполон или заменён")
    обработка.проверить_контекст(план["контекст"])
    обработка.сверить_границы(источник, [план["контекст"]], без_записи=True)
    обработка.требовать(обработка.контекст_снимка(снимок)["экземпляры"] == план["контекст"]["экземпляры"], "после плана появился новый ввод")
    # Поздний служебный вывод не меняет рассмотренную человеческую границу.
    снимок.update({"корень": str(корень), "граница": план["контекст"]["граница"], "sha256": план["контекст"]["sha256"]})
    файлы, записи = построить(снимок, план["решения"], план["каталог"], сохранённые=True)
    обработка.требовать(файлы == план["файлы"] and записи == план["записи"], "план не воспроизводится из выбранных входов")
    основа = план["история"].encode("utf-8")
    обработка.требовать(обработка.хэш(основа) == план["история_sha256"] and сырые.startswith(основа), "история изменилась")
    прежние = обработка.разобрать_историю(основа, задача, план["источник"])
    хвост = события[len(прежние):]
    обработка.требовать(len(хвост) <= len(записи) and all(событие["запись"] == запись for событие, запись in zip(хвост, записи)), "в историю вмешалось другое решение")
    for файл in файлы:
        путь = обработка.локальный_путь(корень, файл["путь"])
        if путь.exists():
            обработка.требовать(обработка.прочитать_файл(путь) == файл["текст"].encode("utf-8"), "материал повреждён или занят")
    обработка.требовать(допуск(корень) == план["допуск"], "допуск изменился перед применением")
    return len(хвост)


def установить(корень, файл):
    путь = обработка.локальный_путь(корень, файл["путь"])
    байты = файл["текст"].encode("utf-8")
    if путь.exists():
        обработка.требовать(обработка.прочитать_файл(путь) == байты, "материал уже занят")
        with путь.open("rb") as поток:
            os.fsync(поток.fileno())
        for предок in путь.parents:
            обработка.синхронизировать_каталог(предок)
            if предок == корень:
                break
        return
    каталог = корень
    for часть in путь.parent.relative_to(корень).parts:
        следующий = каталог / часть
        if not следующий.exists():
            следующий.mkdir()
        обработка.требовать(следующий.is_dir() and not следующий.is_symlink(), "каталог материала подменён")
        обработка.синхронизировать_каталог(каталог)
        каталог = следующий
    # Штатная атомарная установка, в допущенном дереве работает один писатель.
    читатель._установить(путь, байты)
    обработка.синхронизировать_каталог(путь.parent)


def применить(источник, задача, *, корень_репозитория, кэш, план, ожидаемый_хэш):
    корень = Path(корень_репозитория).resolve(strict=True)
    # Ошибки предварительной проверки не скрываются как частичный успех.
    читатель.прочитать_сообщения(источник, задача, корень_репозитория=корень, кэш=кэш, без_записи=True)
    ранее = проверить(источник, задача, корень, план, ожидаемый_хэш)
    результат = {"схема": "fum.применение-свидетельств.1", "план_sha256": ожидаемый_хэш,
                 "применено": False, "ранее_сохранено": ранее, "материалы": [], "результаты": [],
                 "ошибка": None, "завершение_задачи_доказано": False}
    try:
        for файл in план["файлы"]:
            установить(корень, файл)
            результат["материалы"].append(файл["путь"])
        история = план["история_sha256"]
        for запись in план["записи"]:
            обработка.требовать(допуск(корень) == план["допуск"], "допуск изменился между записями")
            итог = обработка.сохранить_обработку(источник, задача, корень_репозитория=корень,
                кэш=кэш, запись=запись, ожидаемая_история=история)
            результат["результаты"].append(итог)
            история = итог["история_sha256"]
        проверить(источник, задача, корень, план, ожидаемый_хэш)
        результат["применено"] = True
    except (OSError, ValueError) as ошибка:
        результат["ошибка"] = str(ошибка)
    return результат

#!/usr/bin/env python3
"""Проверяет заявленный объём задачи; не перехватывает завершение Codex."""
import argparse
import importlib.util
import json
from pathlib import Path
import re
import sys
import subprocess
import time
import uuid

setattr(sys, "dont_write_bytecode", True)


class ОшибкаПродолжения(ValueError):
    pass


def объект(значение, поля):
    if not isinstance(значение, dict) or set(значение) != set(поля):
        raise ОшибкаПродолжения("неверный набор полей")


def строка(значение):
    if not isinstance(значение, str) or not значение.strip():
        raise ОшибкаПродолжения("ожидалась непустая строка")
    return значение


def локальный_файл(корень, имя):
    путь = Path(строка(имя))
    if путь.is_absolute() or any(часть in (".", "..") for часть in имя.split("/")) or str(путь) != имя:
        raise ОшибкаПродолжения("неканонический локальный путь")
    if путь.parts[0].casefold() == "proyekcii":
        raise ОшибкаПродолжения("производная проекция не является источником полномочий")
    текущий = корень
    for часть in путь.parts:
        if часть not in {потомок.name for потомок in текущий.iterdir()}:
            raise ОшибкаПродолжения("путь не найден с точным регистром")
        текущий = текущий / часть
        if текущий.is_symlink():
            raise ОшибкаПродолжения("символическая ссылка запрещена")
    if not текущий.is_file():
        raise ОшибкаПродолжения("ожидался обычный файл")
    return текущий


def разделы_запроса(текст):
    заголовки = []
    смещение = 0
    ограда = None
    комментарий = False
    for линия in текст.splitlines(keepends=True):
        чистая = линия.strip()
        if ограда is not None:
            if re.fullmatch(re.escape(ограда[0]) + "{" + str(ограда[1]) + ",}", чистая):
                ограда = None
        elif комментарий:
            комментарий = "-->" not in линия
        elif "<!--" in линия:
            комментарий = "-->" not in линия.split("<!--", 1)[1]
        else:
            граница = re.match(r"^ {0,3}(`{3,}|~{3,})", линия)
            заголовок = re.fullmatch(r"## ([^\r\n]+)\r?\n?", линия)
            if граница:
                ограда = (граница[1][0], len(граница[1]))
            elif заголовок:
                заголовки.append((заголовок[1].rstrip(), смещение, смещение + len(линия)))
        смещение += len(линия)
    if ограда is not None or комментарий:
        raise ОшибкаПродолжения("незавершённая дословная или служебная область запроса")
    разделы = {}
    for номер, (имя, _, начало) in enumerate(заголовки):
        конец = заголовки[номер + 1][1] if номер + 1 < len(заголовки) else len(текст)
        разделы.setdefault(имя, []).append(текст[начало:конец])
    return разделы


def проверить_основание(корень, основание, идентификатор, источники, входы=None):
    объект(основание, ("запрос", "цитата"))
    имя = строка(основание["запрос"])
    if re.fullmatch(r"Журнал/[^/]+/запрос\.md", имя) is None:
        raise ОшибкаПродолжения("основание должно ссылаться на исходный запрос")
    if имя not in источники:
        байты = локальный_файл(корень, имя).read_bytes()
        if входы is not None:
            входы.setdefault(имя, байты)
        разделы = разделы_запроса(байты.decode("utf-8"))
        тексты = разделы.get("Текст запроса", [])
        задачи = разделы.get("Идентификатор сеанса Codex", [])
        if len(тексты) != 1 or len(задачи) != 1 or задачи[0].strip() != "Codex-Thread-ID: " + идентификатор:
            raise ОшибкаПродолжения("отсутствующий, неоднозначный или чужой служебный раздел задачи")
        источники[имя] = тексты[0]
    if строка(основание["цитата"]) not in источники[имя]:
        raise ОшибкаПродолжения("цитата не найдена в дословном тексте запроса")


def определить_продолжение(корень, план, идентификатор, входы=None):
    объект(план, ("схема", "задача", "режим", "остановка", "работы"))
    if план["схема"] != "fum.продолжение-задачи.1":
        raise ОшибкаПродолжения("неизвестная схема")
    if str(uuid.UUID(идентификатор)) != идентификатор or план["задача"] != идентификатор:
        raise ОшибкаПродолжения("идентификатор корневой задачи не совпадает")
    if план["режим"] not in ("постоянная", "разовая"):
        raise ОшибкаПродолжения("неизвестный режим задачи")
    источники = {}
    if план["остановка"] is not None:
        проверить_основание(корень, план["остановка"], идентификатор, источники, входы)
        return {"схема": "fum.решение-продолжения.1", "задача": идентификатор,
                "решение": "остановлено-пользователем", "следующая_работа": None, "ожидающие_работы": []}
    работы = план["работы"]
    if not isinstance(работы, list) or not работы:
        raise ОшибкаПродолжения("пустой перечень не доказывает завершение объёма")
    известные = set()
    доступные = []
    ожидающие = []
    for работа in работы:
        объект(работа, ("идентификатор", "действие", "состояние", "основание", "свидетельство"))
        имя = строка(работа["идентификатор"])
        if имя in известные:
            raise ОшибкаПродолжения("идентификатор работы повторён")
        известные.add(имя)
        строка(работа["действие"])
        проверить_основание(корень, работа["основание"], идентификатор, источники, входы)
        состояние = работа["состояние"]
        if состояние == "доступна":
            if работа["свидетельство"] is not None:
                raise ОшибкаПродолжения("доступная работа не имеет терминального свидетельства")
            доступные.append(имя)
        elif состояние in ("завершена", "ожидает-ответа"):
            строка(работа["свидетельство"])
            if состояние == "ожидает-ответа":
                ожидающие.append(имя)
        else:
            raise ОшибкаПродолжения("неизвестное состояние работы")
    if доступные:
        решение = "продолжить"
    elif ожидающие:
        решение = "ожидать-ответа"
    else:
        решение = "завершить"
    return {"схема": "fum.решение-продолжения.1", "задача": идентификатор, "решение": решение,
            "следующая_работа": доступные[0] if решение == "продолжить" else None,
            "ожидающие_работы": ожидающие}


def без_повторных_ключей(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ОшибкаПродолжения("повторный ключ JSON")
        результат[ключ] = значение
    return результат


def проверить_третий_реестр(корень, задача, байты_реестра, путь_плана, прежний, метки, повторные_сверки=None):
    """Частичный остаток v3 не выдаётся за полное завершение задачи."""
    входы = {f"Планирование/задачи/{задача}/обязательства.json": байты_реестра}
    if путь_плана is not None:
        байты_плана = локальный_файл(корень, путь_плана).read_bytes()
        входы[путь_плана] = байты_плана
        план = прежний.разобрать(байты_плана)
        объект(план, ("схема", "задача", "режим", "остановка", "работы"))
        if (план["схема"] != "fum.продолжение-задачи.2" or план["задача"] != задача
                or план["режим"] not in ("разовая", "постоянная")):
            raise ОшибкаПродолжения("неверная граница исторического плана")
        if прежний.проверить_остановку(корень, план, задача, разделы_запроса):
            return {"схема": "fum.решение-продолжения.2", "задача": задача,
                    "решение": "остановлено-пользователем", "следующая_работа": None,
                    "ожидающие_работы": [], "незавершённые_обязательства": []}
    начало = time.perf_counter_ns()
    исход = "ошибка"
    описание = importlib.util.spec_from_file_location(
        "обязательства_третьей_версии", Path(__file__).resolve().with_name("обязательства_задачи.py"))
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    try:
        if задача != модуль.ГРАНИЦА_ЗАДАЧИ["задача"]:
            raise ОшибкаПродолжения("для этой задачи нет закреплённого импорта v3")
        остаток = модуль.проверить_остаток(корень, кандидат=байты_реестра)
        for путь, байты in входы.items():
            if локальный_файл(корень, путь).read_bytes() != байты:
                raise ОшибкаПродолжения("вход изменился во время проверки остатка")
        вершина = модуль.выполнить_чтение_репозитория(корень, "rev-parse", "--verify", "HEAD").decode().strip()
        if вершина != остаток["вершина"]:
            raise ОшибкаПродолжения("HEAD изменился перед решением о продолжении")
        if повторные_сверки is not None:
            повторные_сверки.append(lambda: сверить_входы(корень, входы))
        исход = "успешно"
        return {"схема": "fum.решение-продолжения.2", "задача": задача,
                "решение": "продолжить", "следующая_работа": остаток["следующая_работа"],
                "ожидающие_работы": [запись["работа"] for запись in остаток["работы_в_ожидании"]],
                "незавершённые_обязательства": остаток["остаток_обязательств"],
                "HEAD": вершина, "доказательства": {}}
    except модуль.ОшибкаОтчёта as ошибка:
        raise ОшибкаПродолжения(str(ошибка)) from ошибка
    finally:
        метки.append({"метка": "частичный остаток третьей версии", "исход": исход,
                      "длительность_нс": time.perf_counter_ns() - начало})


def сверить_входы(корень, входы, отсутствующий=None):
    for путь, байты in входы.items():
        if локальный_файл(корень, путь).read_bytes() != байты:
            raise ОшибкаПродолжения("вход изменился между проверками обязательств и сообщений")
    if отсутствующий is not None and (отсутствующий.exists() or отсутствующий.is_symlink()):
        raise ОшибкаПродолжения("реестр появился между проверками обязательств и сообщений")


def выполнить():
    параметры = argparse.ArgumentParser(description=__doc__)
    параметры.add_argument("--корень-репозитория", type=Path, required=True)
    параметры.add_argument("--план")
    параметры.add_argument("--codex-thread-id", required=True)
    параметры.add_argument("--исходник", type=Path, required=True)
    параметры.add_argument("--кэш", type=Path)
    параметры.add_argument("--вид-коммита", choices=("контрольный", "итоговый-этапа"))
    параметры.add_argument("--перед-завершением", action="store_true")
    параметры.add_argument("--профиль", action="store_true")
    аргументы = параметры.parse_args()
    начало = time.perf_counter_ns()
    исход = "ошибка"
    метки = []
    повторные_сверки = []
    try:
        корень = аргументы.корень_репозитория.resolve(strict=True)
        if str(uuid.UUID(аргументы.codex_thread_id)) != аргументы.codex_thread_id:
            raise ОшибкаПродолжения("неканонический идентификатор задачи")
        путь_модуля = Path(__file__).resolve().with_name("обязательства_задачи_v2.py")
        описание = importlib.util.spec_from_file_location("обязательства_продолжения", путь_модуля)
        обязательства = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(обязательства)
        вершина_начала = None
        if (корень / ".git").exists():
            вершина_начала = обязательства.ЧтениеГит(корень).выполнить("rev-parse", "--verify", "HEAD").decode().strip()
        реестр = корень / f"Планирование/задачи/{аргументы.codex_thread_id}/обязательства.json"
        if реестр.exists() or реестр.is_symlink() or аргументы.план is None:
            байты = локальный_файл(корень, str(реестр.relative_to(корень))).read_bytes()
            данные = обязательства.разобрать(байты)
            if isinstance(данные, dict) and данные.get("схема") == "fum.обязательства-задачи.3":
                результат = проверить_третий_реестр(корень, аргументы.codex_thread_id, байты,
                                                   аргументы.план, обязательства, метки, повторные_сверки)
            else:
                результат = обязательства.проверить_обязательства(корень, аргументы.codex_thread_id, аргументы.план, разделы_запроса, метки, повторные_сверки)
        else:
            история = None
            if (корень / ".git").exists() or (корень / ".git").is_symlink():
                история = обязательства.ПроверкаОбязательств(корень, аргументы.codex_thread_id, разделы_запроса, метки)
                версии = история.гит.версии_пути(list(история.родители), история.путь_реестра)
                if any(версии.values()):
                    raise ОшибкаПродолжения("удаление рабочего реестра не разрешает возврат к историческому плану")
            входы = {аргументы.план: локальный_файл(корень, аргументы.план).read_bytes()}
            план = json.loads(входы[аргументы.план].decode("utf-8"), object_pairs_hook=без_повторных_ключей)
            объект(план, ("схема", "задача", "режим", "остановка", "работы"))
            if план.get("остановка") is not None:
                обязательства.проверить_остановку(корень, план, аргументы.codex_thread_id, разделы_запроса)
            результат = определить_продолжение(корень, план, аргументы.codex_thread_id, входы)
            if результат["решение"] != "остановлено-пользователем":
                if реестр.exists() or реестр.is_symlink():
                    raise ОшибкаПродолжения("реестр появился во время проверки исторического плана")
                for путь, байты in входы.items():
                    if локальный_файл(корень, путь).read_bytes() != байты:
                        raise ОшибкаПродолжения("вход исторического плана изменился перед решением")
                if история is not None and история.гит.выполнить("rev-parse", "--verify", "HEAD").decode().strip() != история.вершина:
                    raise ОшибкаПродолжения("HEAD изменился перед решением исторического плана")
                повторные_сверки.append(lambda: сверить_входы(корень, входы, реестр))
                if история is not None:
                    повторные_сверки.append(история.проверить_границу)
            if аргументы.перед_завершением and план["режим"] == "постоянная" and результат["решение"] == "завершить":
                результат["решение"] = "продолжить"
                результат["причина"] = "исторический план не доказывает завершение постоянной задачи без реестра v2"
        результат["вид_коммита"] = аргументы.вид_коммита
        начало_сообщений = time.perf_counter_ns()
        сводка = None
        решение = результат["решение"]
        if решение != "остановлено-пользователем":
            # Изолированный Python не добавляет scripts в sys.path.
            sys.path.insert(0, str(Path(__file__).resolve().parent))
            import обработка_сообщений as обработка
            остаток = обработка.получить_остаток(аргументы.исходник, аргументы.codex_thread_id,
                корень_репозитория=корень, кэш=аргументы.кэш, без_записи=True)
            вершина_конца = обработка.гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip()
            if вершина_конца != вершина_начала or результат.get("HEAD", вершина_начала) != вершина_начала:
                raise ОшибкаПродолжения("HEAD изменился между проверками обязательств и сообщений")
            for сверка in повторные_сверки:
                сверка()
            сводка = {"всего": len(остаток["сообщения"]), "остаток": len(остаток["остаток"]),
                      "полнота_источника": остаток["полнота_источника"],
                      "непроверенный_хвост": остаток["непроверенный_хвост"],
                      "разбор_сообщений_завершён": остаток["разбор_сообщений_завершён"]}
            if not сводка["разбор_сообщений_завершён"]:
                решение = "продолжить"
        метки.append({"метка": "остаток сообщений без записи", "исход": "пропущен по остановке" if сводка is None else "успешно",
                      "длительность_нс": time.perf_counter_ns() - начало_сообщений})
        результат = {"схема": "fum.решение-продолжения.3", "задача": аргументы.codex_thread_id,
                     "решение": решение, "обязательства": результат, "сообщения": сводка}
        print(json.dumps(результат, ensure_ascii=False, sort_keys=True))
        исход = результат["решение"]
        return 3 if аргументы.перед_завершением and исход == "продолжить" else 0
    except (OSError, ValueError, TypeError, KeyError, IndexError, ImportError, subprocess.SubprocessError) as ошибка:
        print("ошибка: " + str(ошибка), file=sys.stderr)
        return 2
    finally:
        if аргументы.профиль:
            try:
                print("FUM-PROFILE " + json.dumps({"схема": "fum.профиль-продолжения.1",
                      "метка": "проверка решения о продолжении", "исход": исход,
                      "длительность_нс": time.perf_counter_ns() - начало, "стадии": метки}, ensure_ascii=False), file=sys.stderr)
            except OSError:
                pass


if __name__ == "__main__":
    raise SystemExit(выполнить())

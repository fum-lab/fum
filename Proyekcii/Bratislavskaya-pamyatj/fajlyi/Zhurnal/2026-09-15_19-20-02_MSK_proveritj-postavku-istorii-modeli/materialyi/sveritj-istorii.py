"""Сверить новый артефакт с принятой историей без чтения native JSONL."""
import hashlib
import json
from pathlib import Path

корень = Path(__file__).resolve().parents[3]
прежний = корень / 'Журнал/2026-09-15_18-29-25_MSK_закрепить-восемь-решений-обработки/материалы/история-модели-и-усилия.jsonl'
новый = корень / 'Журнал/2026-09-15_19-05-01_MSK_сохранять-наблюдаемую-историю-модели/материалы/история-корневой-задачи.json'
старые = [json.loads(строка) for строка in прежний.read_bytes().splitlines()]
данные = json.loads(новый.read_bytes())
assert len(старые) == len(данные['события']) == 4
for старое, событие in zip(старые, данные['события']):
    assert старое['задача'] == данные['задача']
    assert (старое['model'], старое['effort'], старое['timestamp']) == (событие['модель'], событие['усилие'], событие['время'])
    assert событие['позиция'] == {ключ: старое['источник'][ключ] for ключ in ('начало', 'конец', 'sha256')}
    assert старое['инициатор'] == событие['инициатор'] == 'unknown'
    assert старое['причина'] == событие['причина'] == 'unknown'
print(json.dumps({'схема': 'fum.сверка-историй-модели.1', 'совпало_событий': 4,
    'повторное_чтение_native': False, 'пары': [[событие['модель'], событие['усилие']] for событие in данные['события']],
    'источники': [{'путь': путь.relative_to(корень).as_posix(), 'sha256': hashlib.sha256(путь.read_bytes()).hexdigest()}
                  for путь in (прежний, новый)]}, ensure_ascii=False))

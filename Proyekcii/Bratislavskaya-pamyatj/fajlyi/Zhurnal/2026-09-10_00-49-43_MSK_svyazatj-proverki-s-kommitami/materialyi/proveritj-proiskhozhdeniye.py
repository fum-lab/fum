"""Сверить снимок старого реестра с локальными Git-объектами и картой переноса."""
import hashlib
import json
import sys
from pathlib import Path


корень = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(корень / "Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts"))
from связь_отпечатка_с_коммитом import выполнить_чтение_репозитория


материалы = Path(__file__).parent
карта = json.loads((материалы / "происхождение-обязательств.json").read_text())
описание = карта["исторический_снимок_реестра"]
байты = выполнить_чтение_репозитория(корень, "show", описание["коммит"] + ":" + описание["путь"])
if hashlib.sha256(байты).hexdigest() != описание["sha256"]:
    raise AssertionError("Неверный хэш исторического снимка")
if байты != (материалы / "исторический-реестр-обязательств.json").read_bytes():
    raise AssertionError("Архивная копия не совпадает с Git-объектом")
реестр = json.loads(байты)
if реестр["исходный_коммит"] != карта["исторический_генезис"]:
    raise AssertionError("Смешаны генезис и снимок реестра")
определения = {запись["идентификатор"]: запись for запись in реестр["обязательства"]}
if set(определения) != set(карта["источники"]):
    raise AssertionError("Снимок не покрывает перенесённые определения")
for имя, запись in определения.items():
    цитаты = карта["источники"][имя]
    if len(цитаты) != 1 or цитаты[0]["цитата"] != запись["основание"]["цитата"]:
        raise AssertionError("Цитата переноса отличается от определения")
print(json.dumps({"состояние": "подтверждено", "определений": len(определения), "коммит_снимка": описание["коммит"], "sha256": описание["sha256"]}, ensure_ascii=False))

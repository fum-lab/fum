"""Приёмка готового CLI на двух явно переданных приватных префиксах.

Исходники и прежний контейнер только читаются. Сырые результаты остаются
в новом приватном каталоге. Публикуемый отчёт содержит размеры, хэши и исходы.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import time


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def сохранить(путь, данные):
    with путь.open("xb") as файл:
        файл.write(данные)
        файл.flush()
        os.fsync(файл.fileno())


def выполнить():
    if not __debug__:
        raise SystemExit("Приёмка запрещена при отключённых проверках Python.")
    разбор = argparse.ArgumentParser(description=__doc__)
    for имя in ("программа", "исходный", "дополненный", "прежний-архив", "приватный-каталог", "отчёт", "задача", "коммит", "хэш-программы"):
        разбор.add_argument("--" + имя, required=True)
    параметры = vars(разбор.parse_args())
    программа = Path(параметры["программа"]).resolve(strict=True)
    исходный = Path(параметры["исходный"]).resolve(strict=True)
    дополненный = Path(параметры["дополненный"]).resolve(strict=True)
    прежний = Path(параметры["прежний_архив"]).resolve(strict=True)
    приватный = Path(параметры["приватный_каталог"])
    отчёт = Path(параметры["отчёт"])
    assert хэш(программа.read_bytes()) == параметры["хэш_программы"]
    assert re.fullmatch(r"[0-9a-f]{40}", параметры["коммит"])
    assert not приватный.exists() and not отчёт.exists()
    приватный.mkdir(mode=0o700)
    архив = приватный / "архив"
    архив.mkdir(mode=0o700)
    сегмент = архив / "сегмент.fumobs"
    прежние_байты = (прежний / сегмент.name).read_bytes()
    сохранить(сегмент, прежние_байты)
    первые_байты = исходный.read_bytes()
    новые_байты = дополненный.read_bytes()
    assert новые_байты.startswith(первые_байты)
    assert len(новые_байты) > len(первые_байты)
    assert первые_байты.endswith(b"\n") and новые_байты.endswith(b"\n")
    измерения = []

    def команда(имя, аргументы, ожидаемый_код=0):
        начало = time.perf_counter_ns()
        результат = subprocess.run([str(программа), *map(str, аргументы)], capture_output=True, timeout=60)
        длительность = time.perf_counter_ns() - начало
        сохранить(приватный / (имя + ".stdout"), результат.stdout)
        сохранить(приватный / (имя + ".stderr"), результат.stderr)
        измерения.append({"стадия": имя, "наносекунды": длительность, "код": результат.returncode})
        assert результат.returncode == ожидаемый_код, имя + ": неожиданный код; диагностика сохранена приватно"
        if ожидаемый_код:
            assert not результат.stdout, имя + ": при отказе опубликован результат"
        return результат.stdout

    базовый = команда("базовое-восстановление", ["replay", архив, параметры["задача"]])
    assert json.loads(базовый)["архив"]["граница"] == {
        "sha256": хэш(первые_байты), "байты": len(первые_байты), "строки": первые_байты.count(b"\n")}
    добавленный = команда("дополнение", ["импорт", дополненный, архив, параметры["задача"]])
    принятые_байты = сегмент.read_bytes()
    assert принятые_байты.startswith(прежние_байты)
    assert len(принятые_байты) > len(прежние_байты)
    граница = json.loads(добавленный)["архив"]["граница"]
    assert граница == {"sha256": хэш(новые_байты), "байты": len(новые_байты), "строки": новые_байты.count(b"\n")}
    повтор = команда("повтор-дополнения", ["импорт", дополненный, архив, параметры["задача"]])
    восстановление = команда("восстановление-дополнения", ["replay", архив, параметры["задача"]])
    assert добавленный == повтор == восстановление
    assert сегмент.read_bytes() == принятые_байты

    # Подменяется один байт времени в КОПИИ: JSON остаётся корректным,
    # длина, UUID и предметные поля не меняются. Хэш старого префикса меняется.
    первая_строка = новые_байты.split(b"\n", 1)[0]
    совпадение = re.search(rb'"timestamp"\s*:\s*"([0-9]{4})-', первая_строка)
    assert совпадение is not None
    позиция = совпадение.start(1) + 3
    подмена = bytearray(новые_байты)
    подмена[позиция] = ord("0") if подмена[позиция] != ord("0") else ord("1")
    json.loads(bytes(подмена).split(b"\n", 1)[0])
    подменённый = приватный / "подменённый-префикс.jsonl"
    сохранить(подменённый, подмена)
    команда("отказ-подмене", ["импорт", подменённый, архив, параметры["задача"]], 2)
    assert сегмент.read_bytes() == принятые_байты
    команда("отказ-усечению", ["импорт", исходный, архив, параметры["задача"]], 2)
    assert сегмент.read_bytes() == принятые_байты
    после_отказов = команда("восстановление-после-отказов", ["replay", архив, параметры["задача"]])
    assert после_отказов == добавленный
    assert исходный.read_bytes() == первые_байты
    assert дополненный.read_bytes() == новые_байты
    assert (прежний / сегмент.name).read_bytes() == прежние_байты
    результат = {
        "схема": "fum.приёмка-продолжения-архива.1",
        "коммит_исходников": параметры["коммит"],
        "sha256_программы": параметры["хэш_программы"],
        "исходный_префикс": {"байты": len(первые_байты), "строки": первые_байты.count(b"\n"), "sha256": хэш(первые_байты)},
        "дополненный_префикс": граница,
        "контейнер_до": {"байты": len(прежние_байты), "sha256": хэш(прежние_байты)},
        "контейнер_после": {"байты": len(принятые_байты), "sha256": хэш(принятые_байты)},
        "результат": "успешно",
        "подтверждено": ["сохранение прежних байтов контейнера при дополнении", "точная граница дополненного источника", "побайтное равенство повтора и восстановления", "отказ корректному JSON с подменённым байтом принятого префикса", "отказ усечению источника", "неизменность контейнера при обоих отказах", "восстановление после отказов", "неизменность обоих исходников и прежнего контейнера"],
        "измерения": измерения,
        "граница": "Два закреплённых приватных префикса одной задачи; отдельный процесс CLI на стадию. Не доказывает живое состояние процесса, интерфейс, защиту от согласованной переписи всей истории или приёмку остальных направлений FUM."
    }
    сохранить(отчёт, (json.dumps(результат, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode())
    print("Дополнение, точный повтор, восстановление и два отказа подтверждены; исходники неизменны.")


if __name__ == "__main__":
    выполнить()

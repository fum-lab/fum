"""Чтение полного достижимого DAG и точного обычного файла без записи в Git."""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path, PurePosixPath

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "fum-otchyotyi-o-zapuskakh-proverok" / "scripts"))
from закрытый_отчёт_из_гита import ОшибкаОтчёта, разобрать_пакет_объектов
from связь_отпечатка_с_коммитом import выполнить_чтение_репозитория
from отчёты_о_запусках_проверок import проверить_аналитический_ключ


def требовать(условие, сообщение):
    if not условие:
        raise ОшибкаОтчёта(сообщение)


def полный_идентификатор(значение):
    требовать(isinstance(значение, str) and re.fullmatch(r"(?:[0-9a-f]{40}|[0-9a-f]{64})", значение), "требуется полный OID")
    return значение


def точный_путь(значение):
    проверить_аналитический_ключ(значение, "путь")
    требовать(isinstance(значение, str) and значение and not any(знак in значение for знак in "\x00\r\n\\:*?[]"), "недопустимый путь")
    путь = PurePosixPath(значение)
    требовать(путь.parts and not путь.is_absolute() and путь.as_posix() == значение and all(часть not in {".", ".."} for часть in путь.parts) and путь.parts[0] != "Proyekcii", "нужен точный канонический путь")
    return путь.parts


def разобрать_типизированный_пакет(ожидаемые, байты):
    """Тип задаёт вызывающий: commit/tree не ослабляют отдельный blob-контракт."""
    требовать(isinstance(ожидаемые, dict) and isinstance(байты, bytes), "неверный пакет")
    for объект, тип in ожидаемые.items():
        полный_идентификатор(объект)
        требовать(тип in {"commit", "tree"}, "неверный ожидаемый тип")
    позиция = 0
    результат = {}
    for объект, тип in ожидаемые.items():
        конец = байты.find(b"\n", позиция)
        требовать(конец >= 0, "неполный заголовок объекта")
        поля = байты[позиция:конец].split(b" ")
        требовать(len(поля) == 3 and поля[:2] == [объект.encode(), тип.encode()] and re.fullmatch(rb"(?:0|[1-9][0-9]*)", поля[2]), "неверный OID, тип или размер объекта")
        try:
            размер = int(поля[2])
        except ValueError as ошибка:
            raise ОшибкаОтчёта("неверный размер объекта") from ошибка
        начало = конец + 1
        конец = начало + размер
        требовать(конец < len(байты) and байты[конец:конец + 1] == b"\n", "неполный объект")
        результат[объект] = байты[начало:конец]
        позиция = конец + 1
    требовать(позиция == len(байты), "лишние байты пакета")
    return результат


def прочитать_объекты(корень, объекты, тип):
    ожидаемые = sorted(set(объекты))
    if not ожидаемые:
        return {}
    for объект in ожидаемые:
        полный_идентификатор(объект)
    пакет = выполнить_чтение_репозитория(корень, "cat-file", "--batch", вход=("\n".join(ожидаемые) + "\n").encode("ascii"))
    if тип == "blob":
        return разобрать_пакет_объектов(ожидаемые, пакет)
    return разобрать_типизированный_пакет(dict.fromkeys(ожидаемые, тип), пакет)


def разобрать_дерево(байты, длина_идентификатора):
    требовать(длина_идентификатора in {20, 32}, "неподдержанный формат Git")
    записи = {}
    позиция = 0
    while позиция < len(байты):
        пробел = байты.find(b" ", позиция)
        конец = байты.find(b"\0", пробел + 1)
        требовать(пробел > позиция and конец > пробел + 1, "повреждённое дерево")
        режим = байты[позиция:пробел]
        имя = байты[пробел + 1:конец]
        требовать(режим in {b"40000", b"100644", b"100755", b"120000", b"160000"} and b"/" not in имя and имя not in {b".", b".."} and имя not in записи, "неверная или неоднозначная запись дерева")
        позиция = конец + 1 + длина_идентификатора
        требовать(позиция <= len(байты), "неполный OID дерева")
        записи[имя] = (режим.decode("ascii"), байты[конец + 1:позиция].hex())
    return записи


def состояния_пути(корень, деревья, путь):
    """Исходный вариант: независимое чтение каждого компонента каждой версии."""
    части = точный_путь(путь)
    состояния = {}
    for коммит, дерево in деревья.items():
        for номер, часть in enumerate(части):
            данные = прочитать_объекты(корень, [дерево], "tree")[дерево]
            запись = разобрать_дерево(данные, len(дерево) // 2).get(часть.encode("utf-8"))
            if запись is None:
                состояния[коммит] = None
                break
            режим, объект = запись
            if номер == len(части) - 1:
                требовать(режим in {"100644", "100755"}, "конечный путь не является обычным файлом")
                состояния[коммит] = (режим, объект)
            else:
                требовать(режим == "40000", "промежуточный путь не является деревом")
                дерево = объект
    return состояния


def прочитать_историю(корень_репозитория, путь):
    корень = Path(корень_репозитория).resolve()
    точный_путь(путь)
    читать = lambda *аргументы: выполнить_чтение_репозитория(корень, *аргументы)
    требовать(Path(os.fsdecode(читать("rev-parse", "--show-toplevel").rstrip(b"\n"))).resolve() == корень, "корень checkout не совпадает")
    вершина = полный_идентификатор(читать("rev-parse", "--verify", "HEAD").decode().strip())
    требовать(читать("rev-parse", "--is-shallow-repository").strip() == b"false", "укороченная история запрещена")
    подмены = Path(os.fsdecode(читать("rev-parse", "--git-path", "info/grafts").rstrip(b"\n")))
    if not подмены.is_absolute():
        подмены = корень / подмены
    требовать(not os.path.lexists(подмены), "grafts запрещены")
    родители = {}
    for строка in читать("rev-list", "--topo-order", "--parents", вершина).decode("ascii").splitlines():
        поля = строка.split(" ")
        for поле in поля:
            полный_идентификатор(поле)
        требовать(поля[0] not in родители and len(set(поля[1:])) == len(поля) - 1, "повторная вершина или родитель")
        родители[поля[0]] = поля[1:]
    требовать(вершина in родители and all(родитель in родители for список in родители.values() for родитель in список), "DAG неполон")
    коммиты = прочитать_объекты(корень, родители, "commit")
    деревья = {}
    for коммит, байты in коммиты.items():
        заголовки = байты.split(b"\n\n", 1)[0].split(b"\n")
        деревья_коммита = [строка[5:].decode("ascii") for строка in заголовки if строка.startswith(b"tree ")]
        сырые_родители = [строка[7:].decode("ascii") for строка in заголовки if строка.startswith(b"parent ")]
        требовать(len(деревья_коммита) == 1 and сырые_родители == родители[коммит], "сырой коммит не совпадает с DAG")
        деревья[коммит] = полный_идентификатор(деревья_коммита[0])
    состояния = состояния_пути(корень, деревья, путь)
    содержимое = прочитать_объекты(корень, [запись[1] for запись in состояния.values() if запись is not None], "blob")
    требовать(читать("rev-parse", "--verify", "HEAD").decode().strip() == вершина, "HEAD изменился во время чтения")
    return {"вершина": вершина, "родители": родители, "деревья": деревья,
            "состояния": состояния, "версии": {коммит: None if запись is None else содержимое[запись[1]] for коммит, запись in состояния.items()}}

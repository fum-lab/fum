"""Сравнить чтение одного принятого отчёта; импорты не входят в время вызова."""
import hashlib
import importlib.util
import json
import statistics
import sys
import time
import tracemalloc
from pathlib import Path
from unittest import mock

корень = Path(__file__).resolve().parents[3]
сценарии = корень / "Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts"
sys.path.insert(0, str(сценарии))
import связь_отпечатка_с_коммитом as адаптер

коммит = "6fc2c7a76dd7d23a703418b4072f0fdc561a4f53"
запрос = "Журнал/2026-09-10_00-49-43_MSK_связать-проверки-с-коммитами/запрос.md"


def загрузить(имя, путь):
    описание = importlib.util.spec_from_file_location(имя, путь)
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    return модуль


пути = {"до": Path(__file__).with_name("читатель-до-пакетного-чтения.py"), "после": сценарии / "закрытый_отчёт_из_гита.py"}
модули = {имя: загрузить("читатель_" + имя, путь) for имя, путь in пути.items()}
чтение = адаптер.выполнить_чтение_репозитория


def измерить(модуль):
    наблюдение = {"вызовов_git": 0, "время_git_нс": 0, "получено_байт": 0}

    def считать(*аргументы, **параметры):
        начало = time.perf_counter_ns()
        байты = чтение(*аргументы, **параметры)
        наблюдение["время_git_нс"] += time.perf_counter_ns() - начало
        наблюдение["вызовов_git"] += 1
        наблюдение["получено_байт"] += len(байты)
        return байты

    with mock.patch.object(модуль, "выполнить_чтение_репозитория", считать), mock.patch.object(адаптер, "выполнить_чтение_репозитория", считать):
        начало = time.perf_counter_ns()
        процессор = time.process_time_ns()
        результат = модуль.проверить_отчёт_в_коммите(корень, коммит, запрос)
        наблюдение["процессорное_время_питона_нс"] = time.process_time_ns() - процессор
        наблюдение["длительность_нс"] = time.perf_counter_ns() - начало
    if результат["состояние"] != "подтверждён":
        raise AssertionError("Историческая приёмка не подтверждена")
    return наблюдение, результат


режим = sys.argv[1]
if режим not in {"до", "сравнить"}:
    raise SystemExit("Ожидалось до или сравнить")
имена = ["до"] if режим == "до" else ["до", "после"]
эталон = None
for имя in имена:
    _, результат = измерить(модули[имя])
    if эталон is not None and результат != эталон:
        raise AssertionError("Результаты вариантов расходятся")
    эталон = результат
серии = {имя: [] for имя in имена}
порядки = []
for номер in range(7):
    порядок = имена if номер % 2 == 0 else list(reversed(имена))
    порядки.append(порядок)
    for имя in порядок:
        наблюдение, результат = измерить(модули[имя])
        if результат != эталон:
            raise AssertionError("Результат изменился между измерениями")
        серии[имя].append(наблюдение)
память = {}
for имя in имена:
    tracemalloc.start()
    модули[имя].проверить_отчёт_в_коммите(корень, коммит, запрос)
    _, пик = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    память[имя] = пик
итог = {
    "схема": "fum.профиль-чтения-отчёта.1", "коммит": коммит, "запрос": запрос,
    "граница": "Импорты выполнены заранее. Один прогрев каждого варианта, семь повторов с чередованием. Время включает дочерние Git-процессы; процессорное время Python их не включает. Память Python измерена отдельно, вне временной серии; память Git не измерена. Это не холодный дисковый кеш и не время запуска CLI.",
    "sha256_исходников": {имя: hashlib.sha256(пути[имя].read_bytes()).hexdigest() for имя in имена},
    "порядки": порядки, "наблюдения": серии,
    "медианы_наносекунды": {имя: statistics.median(строка["длительность_нс"] for строка in строки) for имя, строки in серии.items()},
    "пиковая_память_питона_байт": память, "проверенный_результат": эталон,
}
выход = Path(__file__).with_name("профиль-до.json" if режим == "до" else "профиль-сравнения.json")
выход.write_text(json.dumps(итог, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
print(json.dumps({"медианы_мс": {имя: значение / 1e6 for имя, значение in итог["медианы_наносекунды"].items()}, "вызовы_git": {имя: sorted({строка["вызовов_git"] for строка in строки}) for имя, строки in серии.items()}}, ensure_ascii=False))

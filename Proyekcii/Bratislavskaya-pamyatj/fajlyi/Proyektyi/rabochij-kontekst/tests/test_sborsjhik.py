"""Независимые ожидания открытой синтетики, без вычисления эталона сборщиком."""
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

КОРЕНЬ = Path(__file__).resolve().parents[1]


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + '\n').encode()


def снимок():
    return json.loads((КОРЕНЬ / 'фикстуры/снимок.json').read_bytes())


def заменить_события(вход, события):
    сырьё = ''.join(байты(событие).decode() for событие in события)
    источник = вход['источники'][0]
    источник['данные'] = сырьё
    источник['байты'] = len(сырьё.encode())
    источник['хэш'] = hashlib.sha256(сырьё.encode()).hexdigest()


class Сборщик(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        описание = importlib.util.spec_from_file_location('сборщик', КОРЕНЬ / 'сборщик.py')
        класс.модуль = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(класс.модуль)

    def test_независимый_эталон_до_экономии(сам):
        вход = снимок()
        ожидания = json.loads((КОРЕНЬ / 'фикстуры/эталон.json').read_bytes())
        for бюджет in (0, 1, 4096, 100000):
            вход['бюджет_байт'] = бюджет
            результат = сам.модуль.собрать(байты(вход))
            записи = {запись['ид']: запись for запись in результат['записи']}
            сам.assertEqual(list(записи), ожидания['порядок'])
            for идентификатор, ожидание in ожидания['записи'].items():
                for поле, значение in ожидание.items():
                    сам.assertEqual(записи[идентификатор][поле], значение, (идентификатор, поле, бюджет))
            сам.assertEqual(результат['незавершённые_обязательства'], ожидания['незавершённые_обязательства'])
            сам.assertEqual(результат['ближайшие_действия'], [])
            сам.assertEqual(результат['конфликты'], ожидания['конфликты'])
            сам.assertFalse(результат['полнота_источников'])
            сам.assertEqual(результат['размер_байт'], len(байты(результат)))
            сам.assertEqual(результат['превышен_бюджет'], len(байты(результат)) > бюджет)

    def test_повтор_и_неизменность(сам):
        вход = байты(снимок())
        сам.assertEqual(сам.модуль.собрать(вход), сам.модуль.собрать(вход))
        with tempfile.TemporaryDirectory() as каталог:
            путь = Path(каталог) / 'вход.json'
            путь.write_bytes(вход)
            до = (путь.read_bytes(), путь.stat().st_mtime_ns)
            вызов = [sys.executable, '-I', '-S', '-B', str(КОРЕНЬ / 'собрать-контекст.py'), '--снимок', str(путь)]
            первый = subprocess.run(вызов, capture_output=True, check=True)
            второй = subprocess.run(вызов, capture_output=True, check=True)
            сам.assertEqual(первый.stdout, второй.stdout)
            сам.assertEqual(первый.stdout, байты(сам.модуль.собрать(вход)))
            сам.assertEqual(до, (путь.read_bytes(), путь.stat().st_mtime_ns))
            сам.assertEqual([путь], list(Path(каталог).iterdir()))

    def test_точное_раскрытие_всех_строк(сам):
        вход = снимок()
        результат = сам.модуль.собрать(байты(вход))
        источники = {источник['ид']: источник for источник in вход['источники']}
        for запись in результат['записи']:
            указатель = запись['указатель']
            сырьё = источники[указатель['источник']]['данные'].encode()
            фрагмент = сырьё[указатель['начало']:указатель['конец']]
            сам.assertEqual(hashlib.sha256(фрагмент).hexdigest(), указатель['хэш'])
            сам.assertEqual(json.loads(фрагмент)['ид'], запись['ид'])
            сам.assertEqual(сырые_строки := сырьё.splitlines(keepends=True)[указатель['строка']-1], фрагмент)

    def test_отмена_только_в_переданном_снимке(сам):
        вход = снимок()
        события = [json.loads(строка) for строка in вход['источники'][0]['данные'].splitlines()]
        старый = copy.deepcopy(вход)
        заменить_события(старый, [событие for событие in события if событие['ид'] != 'ОТМЕНА'])
        результат = сам.модуль.собрать(байты(старый))
        сам.assertEqual(next(з for з in результат['записи'] if з['ид']=='РАЗРЕШЕНИЕ')['состояние'], 'актуально')
        сам.assertEqual(сам.модуль.собрать(байты(вход))['незавершённые_обязательства'], ['ОБЯЗАТЕЛЬСТВО', 'ДУБЛЬ', 'ИСТОРИЯ'])
        сам.assertEqual(сам.модуль.собрать(байты(старый)), результат)
        сам.assertNotEqual(результат['хэш_снимка'], сам.модуль.собрать(байты(вход))['хэш_снимка'])

    def test_неизвестная_доставка_не_подтверждает_актуальность(сам):
        вход = снимок()
        вход['доставка']['подтверждена'] = False
        результат = сам.модуль.собрать(байты(вход))
        сам.assertFalse(результат['полнота_источников'])
        сам.assertEqual(результат['ближайшие_действия'], [])
        сам.assertIn('граница-доставки-не-подтверждена', результат['неполнота'])

    def test_ошибки_закрывают_приём(сам):
        for поле, значение in (('схема', 'иная'), ('бюджет_байт', True), ('время_оценки', 'вчера')):
            вход = снимок(); вход[поле] = значение
            with сам.subTest(поле=поле), сам.assertRaises(ValueError):
                сам.модуль.собрать(байты(вход))
        вход = снимок(); вход['источники'][0]['хэш'] = '0'*64
        with сам.assertRaisesRegex(ValueError, 'хэш'):
            сам.модуль.собрать(байты(вход))
        вход = снимок(); вход['источники'][0]['задача'] = '00000000-0000-0000-0000-000000000099'
        with сам.assertRaises(ValueError): сам.модуль.собрать(байты(вход))
        with сам.assertRaises(ValueError): сам.модуль.собрать(b'{"a":1,"a":2}')

    def test_точная_граница_бюджета_конечна(сам):
        вход = снимок()
        for источник in вход['источники']:
            if источник['данные'] is None: continue
            события = [json.loads(с) for с in источник['данные'].splitlines()]
            for событие in события:
                if 'подробности' in событие: событие['подробности'] = ''
            сырьё = ''.join(байты(с).decode() for с in события)
            источник.update(данные=сырьё, байты=len(сырьё.encode()), хэш=hashlib.sha256(сырьё.encode()).hexdigest())
        пример = сам.модуль.собрать(байты(вход))['размер_байт']
        for бюджет in range(пример-4, пример+5):
            вход['бюджет_байт'] = бюджет
            with tempfile.TemporaryDirectory() as каталог:
                путь = Path(каталог)/'вход.json'; путь.write_bytes(байты(вход))
                процесс = subprocess.run([sys.executable, '-B', str(КОРЕНЬ/'собрать-контекст.py'), '--снимок', str(путь)], capture_output=True, timeout=3, check=True)
            результат = json.loads(процесс.stdout)
            сам.assertEqual(результат['размер_байт'], len(процесс.stdout))
            сам.assertEqual(результат['превышен_бюджет'], len(процесс.stdout)>бюджет)

    def test_нет_ложной_приёмки_по_недоступному_доказательству(сам):
        вход = снимок()
        события = [json.loads(с) for с in вход['источники'][0]['данные'].splitlines()]
        next(с for с in события if с['ид']=='ПРИЁМКА')['доказательства'] = ['ОТСУТСТВУЕТ']
        заменить_события(вход, события)
        результат = сам.модуль.собрать(байты(вход))
        сам.assertIn('ПРИНЯТОЕ', результат['незавершённые_обязательства'])

    def test_будущее_и_собственное_обязательство_не_доказывают_приёмку(сам):
        for вариант in ('будущее', 'самообоснование'):
            вход = снимок()
            события = [json.loads(с) for с in вход['источники'][0]['данные'].splitlines()]
            if вариант == 'будущее':
                next(с for с in события if с['ид']=='ДОКАЗАТЕЛЬСТВО')['порядок'] = 22
            else:
                next(с for с in события if с['ид']=='ПРИЁМКА')['доказательства'] = ['ПРИНЯТОЕ']
            заменить_события(вход, события)
            with сам.subTest(вариант=вариант), сам.assertRaises(ValueError):
                сам.модуль.собрать(байты(вход))

    def test_неполная_приёмка_и_делегированная_отмена_не_закрывают(сам):
        вход = снимок()
        события = [json.loads(с) for с in вход['источники'][0]['данные'].splitlines()]
        next(с for с in события if с['ид']=='ПРИЁМКА')['принимает'].append('НЕТ-ЦЕЛИ')
        отмена = next(с for с in события if с['ид']=='ОТМЕНА')
        отмена['происхождение'] = 'делегирование'; отмена['отменяет'] = ['ОБЯЗАТЕЛЬСТВО']
        заменить_события(вход, события)
        результат = сам.модуль.собрать(байты(вход))
        сам.assertIn('ОБЯЗАТЕЛЬСТВО', результат['незавершённые_обязательства'])
        сам.assertIn('ПРИНЯТОЕ', результат['незавершённые_обязательства'])
        сам.assertEqual(next(с for с in результат['записи'] if с['ид']=='ПРИЁМКА')['состояние'], 'неизвестно')

    def test_неизвестный_формат_не_интерпретируется(сам):
        вход = снимок(); вход['источники'][0]['контракт'] = 'неизвестная-схема.99'
        with сам.assertRaises(ValueError): сам.модуль.собрать(байты(вход))

    def test_одна_группа_вместо_квадратичного_выхода(сам):
        описание = importlib.util.spec_from_file_location('измеритель', КОРЕНЬ / 'профиль.py')
        измеритель = importlib.util.module_from_spec(описание); описание.loader.exec_module(измеритель)
        результат = сам.модуль.собрать(измеритель.нагрузка('конфликт', 400))
        сам.assertEqual(len(результат['конфликты']), 1)
        сам.assertEqual(результат['конфликты'][0]['участники'], [f'ОБ-{н}' for н in range(400)])
        сам.assertLess(результат['размер_байт'], 500000)
        сам.assertEqual(len(результат['незавершённые_обязательства']), 400)

    def test_служебная_отмена_не_создаёт_полномочий(сам):
        вход = снимок()
        события = [json.loads(строка) for строка in вход['источники'][0]['данные'].splitlines()]
        next(з for з in события if з['ид']=='ОТМЕНА')['происхождение'] = 'служебное'
        заменить_события(вход, события)
        результат = сам.модуль.собрать(байты(вход))
        записи = {з['ид']:з for з in результат['записи']}
        сам.assertNotEqual(записи['РАЗРЕШЕНИЕ']['состояние'], 'отменено')
        сам.assertIn('неподтверждённая-отмена:ОТМЕНА', записи['РАЗРЕШЕНИЕ']['причины'])
        сам.assertNotIn('ДЕЙСТВИЕ', результат['ближайшие_действия'])


if __name__ == '__main__':
    unittest.main()

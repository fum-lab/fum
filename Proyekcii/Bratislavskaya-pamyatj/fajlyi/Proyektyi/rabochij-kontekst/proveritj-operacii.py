"""Общие примеры конечных операций, включая отказы на неверных типах."""
import base64
import json
from pathlib import Path
import sys
import unittest

КОРЕНЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(КОРЕНЬ / "общие/Python"))
from поддержка_моделей import КонтрактМоделей

class ПроверкиОпераций(unittest.TestCase):
    def test_общая_матрица(сам):
        модель = {"имя": "Пример", "поля": [{"ключ": "é", "тип": "строка", "присутствие": "обязательно", "null": "нет", "варианты": ["é"]}]}
        for пример in json.loads((КОРЕНЬ / "фикстуры/семантика-операций.json").read_bytes()):
            with сам.subTest(пример["название"]):
                описание = {"схема": "fum.структурный-контракт.1", "числа": "целые64-без-дробей", "модели": [модель], "переменные": [], "результат": пример["выражение"]}
                контракт = КонтрактМоделей(base64.b64encode(json.dumps(описание, ensure_ascii=False).encode()).decode())
                if пример.get("отказ"):
                    with сам.assertRaises(ValueError): контракт.спроецировать(пример["вход"], {}, "")
                else:
                    сам.assertEqual(контракт.спроецировать(пример["вход"], {}, ""), пример["значение"])

if __name__ == "__main__": unittest.main()

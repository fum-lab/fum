"""Общие модели присутствия, строгий JSON и конечные операции проекции."""
import base64
from dataclasses import dataclass
import hashlib
import json
import re
from typing import Generic, TypeVar
import unicodedata

Значение = TypeVar("Значение")
ОТСУТСТВУЕТ = object()


@dataclass(frozen=True)
class Поле(Generic[Значение]):
    состояние: str
    значение: Значение | None = None


def потребовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def целое(значение):
    потребовать(type(значение) is int and -(2**63) <= значение < 2**63, "Число вне профиля Int64")
    return значение


def строка(значение):
    потребовать(type(значение) is str, "Ожидалась строка")
    return значение


def массив(значение):
    потребовать(type(значение) is list, "Ожидался массив")
    return значение


def словарь(значение):
    потребовать(type(значение) is dict, "Ожидался объект")
    return значение


def равны(левое, правое):
    if type(левое) is not type(правое): return False
    if isinstance(левое, list):
        return len(левое) == len(правое) and all(равны(а, б) for а, б in zip(левое, правое))
    if isinstance(левое, dict):
        return левое.keys() == правое.keys() and all(равны(левое[ключ], правое[ключ]) for ключ in левое)
    return левое == правое


def объект(пары):
    результат = {}; нормализованные = set()
    for ключ, значение in пары:
        нормальный = unicodedata.normalize("NFC", ключ)
        потребовать(нормальный not in нормализованные, "Повтор или канонически совпадающие ключи JSON")
        нормализованные.add(нормальный); результат[ключ] = значение
    return результат


def проверить_JSON(значение, глубина=0):
    потребовать(глубина <= 64, "Превышена глубина JSON")
    if значение is None or type(значение) is bool: return
    if type(значение) is int: целое(значение); return
    if isinstance(значение, str): значение.encode("utf8"); return
    if isinstance(значение, list):
        for часть in значение: проверить_JSON(часть, глубина + 1)
        return
    if isinstance(значение, dict):
        объект(значение.items())
        for ключ, часть in значение.items():
            потребовать(isinstance(ключ, str), "Ключ JSON должен быть строкой")
            ключ.encode("utf8"); проверить_JSON(часть, глубина + 1)
        return
    raise ValueError("Дроби и другие значения вне числового профиля")


def разобрать_JSON(данные):
    try:
        текст = данные.decode("utf8") if isinstance(данные, bytes) else данные
        значение = json.loads(текст, object_pairs_hook=объект,
            parse_int=lambda текст: целое(int(текст)),
            parse_float=lambda _: потребовать(False, "Дробные и экспоненциальные токены запрещены профилем"),
            parse_constant=lambda _: потребовать(False, "Неконечное число"))
        проверить_JSON(значение)
        return значение
    except (UnicodeError, RecursionError, TypeError) as ошибка:
        raise ValueError("Повреждённый JSON") from ошибка


def подготовить_снимок(данные, ожидаемый_хэш, задача):
    потребовать(isinstance(данные, bytes) and len(данные) <= 134217728, "Неверный размер снимка")
    потребовать(isinstance(задача, str) and re.fullmatch(r"[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}", задача), "Нужен UUID задачи")
    хэш = hashlib.sha256(данные).hexdigest()
    потребовать(хэш == ожидаемый_хэш, "Не совпал SHA полного артефакта")
    return разобрать_JSON(данные), {"sha256": хэш, "байты": len(данные)}


def ограничить_выход(значение, максимум_байтов):
    потребовать(type(максимум_байтов) is int and 100 <= максимум_байтов <= 1048576, "Неверный бюджет")
    данные = (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode("utf8")
    потребовать(len(данные) <= максимум_байтов, "Бюджет превышен; оригинал не усечён")
    return данные


class КонтрактМоделей:
    def __init__(сам, данные):
        сам.описание = разобрать_JSON(base64.b64decode(данные, validate=True))
        потребовать(сам.описание["схема"] == "fum.структурный-контракт.1" and
            сам.описание["числа"] == "целые64-без-дробей", "Неизвестный профиль моделей")
        сам.модели = {модель["имя"]: модель for модель in сам.описание["модели"]}

    def проверить_тип(сам, тип, значение):
        if тип == "строка": потребовать(isinstance(значение, str), "Ожидалась строка")
        elif тип == "целое": целое(значение)
        elif тип == "логическое": потребовать(type(значение) is bool, "Ожидалось логическое значение")
        elif тип == "JSON": проверить_JSON(значение)
        elif тип.startswith("массив<"):
            потребовать(isinstance(значение, list), "Ожидался массив")
            for часть in значение: сам.проверить_тип(тип[7:-1], часть)
        elif тип.startswith("словарь<"):
            потребовать(isinstance(значение, dict), "Ожидался словарь")
            for часть in значение.values(): сам.проверить_тип(тип[8:-1], часть)
        elif тип in сам.модели: сам.проверить(значение, тип)
        else: raise ValueError("Неизвестный тип")

    def проверить(сам, значение, имя):
        потребовать(isinstance(значение, dict), "Модель требует объект")
        поля = сам.модели[имя]["поля"]
        потребовать(set(значение) <= {поле["ключ"] for поле in поля}, "Неизвестное поле модели")
        for поле in поля:
            часть = значение.get(поле["ключ"], ОТСУТСТВУЕТ)
            if часть is ОТСУТСТВУЕТ:
                потребовать(поле["присутствие"] == "необязательно", "Отсутствует обязательное поле")
            elif часть is None:
                потребовать(поле["null"] == "да", "Null не разрешён для поля")
            else:
                сам.проверить_тип(поле["тип"], часть)
                потребовать(not поле["варианты"] or часть in поле["варианты"], "Неизвестный вариант поля")

    def прочитать_модель(сам, класс, значение, модели):
        сам.проверить(значение, класс.__name__)
        def преобразовать(тип, часть):
            if тип in модели: return сам.прочитать_модель(модели[тип], часть, модели)
            if тип.startswith("массив<"): return [преобразовать(тип[7:-1], элемент) for элемент in часть]
            if тип.startswith("словарь<"): return {ключ: преобразовать(тип[8:-1], элемент) for ключ, элемент in часть.items()}
            return часть
        значения = {}
        for поле in сам.модели[класс.__name__]["поля"]:
            часть = значение.get(поле["ключ"], ОТСУТСТВУЕТ)
            if часть is ОТСУТСТВУЕТ: результат = Поле("отсутствует")
            elif часть is None: результат = Поле("null")
            else:
                результат = преобразовать(поле["тип"], часть)
                if поле["null"] == "да" or поле["присутствие"] == "необязательно": результат = Поле("значение", результат)
            значения[поле["имя"]] = результат
        return класс(**значения)

    def записать_модель(сам, значение):
        def раскрыть(часть):
            if isinstance(часть, Поле):
                if часть.состояние == "отсутствует": return ОТСУТСТВУЕТ
                if часть.состояние == "null": return None
                потребовать(часть.состояние == "значение", "Неизвестное присутствие")
                return раскрыть(часть.значение)
            if type(часть).__name__ in сам.модели: return сам.записать_модель(часть)
            if isinstance(часть, list): return [раскрыть(элемент) for элемент in часть]
            if isinstance(часть, dict): return {ключ: раскрыть(элемент) for ключ, элемент in часть.items()}
            return часть
        результат = {}
        for поле in сам.модели[type(значение).__name__]["поля"]:
            часть = раскрыть(getattr(значение, поле["имя"]))
            if часть is not ОТСУТСТВУЕТ: результат[поле["ключ"]] = часть
        сам.проверить(результат, type(значение).__name__)
        return результат

    def спроецировать(сам, вход, артефакт, задача):
        среда = {"вход": вход, "артефакт": артефакт, "ожидаемаяЗадача": задача}
        def вычислить(узел):
            if isinstance(узел, dict):
                результат = {}
                for ключ, выражение in узел.items():
                    значение = вычислить(выражение)
                    if значение is not ОТСУТСТВУЕТ: результат[ключ] = значение
                return результат
            if not isinstance(узел, list): return узел
            операция, *части = узел
            if операция == "переменная": return среда[части[0]]
            if операция == "если":
                условие = вычислить(части[0])
                потребовать(type(условие) is bool, "Условие не является логическим")
                return вычислить(части[1] if условие else части[2])
            аргументы = [вычислить(часть) for часть in части]
            if операция == "null": return None
            if операция == "истина": return True
            if операция == "ложь": return False
            if операция == "массив": return аргументы
            if операция == "путь":
                значение = аргументы[0]
                for часть in аргументы[1:]:
                    if значение is None or значение is ОТСУТСТВУЕТ: return значение
                    if isinstance(значение, dict): значение = значение.get(строка(часть), ОТСУТСТВУЕТ)
                    elif isinstance(значение, list) and type(часть) is int and 0 <= часть < len(значение): значение = значение[часть]
                    else: raise ValueError("Путь не соответствует структуре")
                return значение
            if операция == "первый": return массив(аргументы[0])[0] if массив(аргументы[0]) else None
            if операция == "без-полей":
                if аргументы[0] is None: return None
                исключённые = {строка(ключ) for ключ in массив(аргументы[1])}
                return {ключ: значение for ключ, значение in словарь(аргументы[0]).items() if ключ not in исключённые}
            if операция == "равно": return равны(аргументы[0], аргументы[1])
            if операция == "не-null": return аргументы[0] is not None and аргументы[0] is not ОТСУТСТВУЕТ
            if операция == "длина": return len(аргументы[0])
            if операция == "вычесть": return целое(целое(аргументы[0]) - целое(аргументы[1]))
            if операция == "потребовать-равно":
                потребовать(равны(аргументы[0], аргументы[1]), "Не совпало обязательное значение")
                return True
            if операция == "потребовать-ложь-или-отсутствие":
                потребовать(аргументы[0] is False or аргументы[0] is ОТСУТСТВУЕТ, "Оболочка сообщает ошибку")
                return True
            if операция == "потребовать-положительное":
                потребовать(целое(аргументы[0]) > 0, "Нужно положительное целое")
                return True
            if операция == "разобрать-JSON":
                значение = разобрать_JSON(строка(аргументы[0])); сам.проверить(значение, строка(аргументы[1])); return значение
            if операция == "собрать-вложенные":
                поле = строка(аргументы[1])
                return [элемент for родитель in массив(аргументы[0]) for элемент in массив(словарь(родитель)[поле])]
            if операция == "проверить-варианты":
                поле = строка(аргументы[1]); варианты = словарь(аргументы[2])
                for элемент in массив(аргументы[0]):
                    потребовать(isinstance(элемент, dict), "Вариант требует объект")
                    тип = элемент.get(поле); потребовать(isinstance(тип, str) and тип in варианты, "Неизвестный вариант элемента")
                    модель = строка(варианты[тип])
                    if модель != "JSON": сам.проверить(элемент, модель)
                return True
            if операция == "выбрать-вложенный":
                родители, поле, дискриминатор, вариант, текст, пробелы = аргументы
                поле = строка(поле); дискриминатор = строка(дискриминатор); текст = строка(текст)
                выбранный = None; пробелы = {целое(часть) for часть in массив(пробелы)}
                for номерРодителя, родитель in enumerate(массив(родители)):
                    последний = None
                    for номер, элемент in enumerate(массив(словарь(родитель)[поле])):
                        if равны(словарь(элемент)[дискриминатор], вариант) and any(ord(символ) not in пробелы for символ in строка(элемент[текст])):
                            последний = {"значение": элемент, "родитель": родитель, "номерРодителя": номерРодителя, "номер": номер}
                    if выбранный is None and последний is not None: выбранный = последний
                return выбранный
            if операция == "группировать":
                счётчики = {}; поле = строка(аргументы[1])
                for элемент in массив(аргументы[0]):
                    ключ = строка(словарь(элемент)[поле]); счётчики[ключ] = целое(счётчики.get(ключ, 0) + 1)
                return объект(счётчики.items())
            if операция == "убрать-выбранный":
                счётчики = {ключ: целое(число) for ключ, число in словарь(аргументы[0]).items()}
                if аргументы[1] is not None and аргументы[1] is not ОТСУТСТВУЕТ:
                    ключ = строка(аргументы[1]); счётчики[ключ] = целое(счётчики[ключ] - 1)
                return {ключ: число for ключ, число in счётчики.items() if число}
            if операция == "считать-не-null":
                поле = строка(аргументы[1])
                return sum(словарь(элемент)[поле] is not None for элемент in массив(аргументы[0]))
            if операция == "указатель":
                сегменты = []
                for часть in массив(аргументы[0]):
                    потребовать(type(часть) in (str, int), "Неверный сегмент указателя")
                    if type(часть) is int: целое(часть)
                    сегменты.append(str(часть).replace("\u007e", "\u007e0").replace("/", "\u007e1"))
                return "/".join([""] + сегменты)
            raise ValueError("Неизвестная операция проекции")
        try:
            for переменная in сам.описание["переменные"]: среда[переменная["имя"]] = вычислить(переменная["значение"])
            return вычислить(сам.описание["результат"])
        except (KeyError, TypeError, IndexError, UnicodeError, RecursionError) as ошибка:
            raise ValueError("Неверный вход конечной проекции") from ошибка

@Test func восстановлениеПроверяетПорядокИКаждуюОпору() {
    func снимок(_ номер: UInt8, head: String = "h", ref: String = "r",
                режим: String = "100644", байты: Data = Data([1]), лишний: Bool = false)
        -> СнимокВосстановленияFUMA {
        var узлы = [УзелСнимкаВосстановленияFUMA(путь: Data("fuma/a".utf8), режим: режим, байты: байты)]
        if лишний { узлы.append(.init(путь: Data("fuma/b".utf8), режим: режим, байты: байты)) }
        return .init(head: head, ref: ref, индекс: Data([номер]), узлы: узлы)
    }
    let ноль = снимок(0), один = снимок(1), два = снимок(2)
    let первый = ШагВосстановленияFUMA(идентификатор: "move", до: ноль, после: один)
    let второй = ШагВосстановленияFUMA(идентификатор: "rewrite", до: один, после: два)
    let шаги = [первый, второй]
    for квитанции in [["rewrite"], ["rewrite", "move"], ["move", "move"]] {
        #expect(СверкаВосстановленияFUMA.проверить(шаги: шаги, квитанции: квитанции,
            намерениеБезКвитанции: nil, наблюдение: один) == .неверныеДанные)
    }
    #expect(СверкаВосстановленияFUMA.проверить(шаги: шаги, квитанции: ["move"],
        намерениеБезКвитанции: "rewrite", наблюдение: один) == .неизвестныйИсход)
    for чужой in [снимок(1, head: "другой"), снимок(1, ref: "другая"),
                  снимок(1, режим: "100755"), снимок(1, байты: Data([2])), снимок(1, лишний: true)] {
        #expect(СверкаВосстановленияFUMA.проверить(шаги: шаги, квитанции: ["move"],
            намерениеБезКвитанции: nil, наблюдение: чужой) == .дрейф)
    }
    let повтор = ШагВосстановленияFUMA(идентификатор: "move", до: один, после: два)
    let разрыв = ШагВосстановленияFUMA(идентификатор: "rewrite", до: ноль, после: два)
    for неверные in [[первый, повтор], [первый, разрыв]] {
        #expect(СверкаВосстановленияFUMA.проверить(шаги: неверные, квитанции: [],
            намерениеБезКвитанции: nil, наблюдение: ноль) == .неверныеДанные)
    }
}

private struct ВыходнойСнимокТестаFUMA {
    let корень: URL
    let записи: [ЗаписьФайлаКаноническогоДереваFUMA]
    let хэшДерева: String
    let список: Data

    func проверить() throws {
        try ПроверкаКаноническогоДереваFUMA.проверить(
            кореньРепозитория: корень,
            исходныйКорень: "Приложения/FUMA",
            версия: ФорматировщикПутейFUMA.версия,
            исходныйКоммит: String(repeating: "a", count: 40),
            деревоИсточника: String(repeating: "b", count: 40),
            хэшВыходногоДерева: хэшДерева,
            ожидаемыеЗаписи: записи,
            байтыСпискаПутей: список)
    }
}

private func валидныйВыходнойСнимокТестаFUMA() throws -> ВыходнойСнимокТестаFUMA {
    let корень = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString, isDirectory: true)
    let каталог = корень.appendingPathComponent("fuma", isDirectory: true)
    let файл = каталог.appendingPathComponent("пакет.swift")
    try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
    let байты = Data("исходник\n".utf8)
    try байты.write(to: файл)
    try FileManager.default.setAttributes([.posixPermissions: 0o644], ofItemAtPath: файл.path)
    let sha256 = SHA256.hash(data: байты).map { String(format: "%02x", $0) }.joined()
    let записи = [ЗаписьФайлаКаноническогоДереваFUMA(путь: "fuma/пакет.swift", режимGit: "100644", sha256: sha256)]
    let хэшДерева = try ПроверкаКаноническогоДереваFUMA.хэшДерева(записи)
    let список = try ПроверкаКаноническогоДереваFUMA.списокПутей(
        версия: ФорматировщикПутейFUMA.версия,
        исходныйКоммит: String(repeating: "a", count: 40),
        деревоИсточника: String(repeating: "b", count: 40),
        хэшВыходногоДерева: хэшДерева,
        записи: записи)
    return .init(корень: корень, записи: записи, хэшДерева: хэшДерева, список: список)
}


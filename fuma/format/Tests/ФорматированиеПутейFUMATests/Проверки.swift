    func снимок(_ индекс: UInt8, _ путь: String) -> СнимокВосстановленияFUMA {
        .init(head: "head", ref: "refs/heads/test", индекс: Data([индекс]),
              узлы: [.init(путь: Data(путь.utf8), режим: "100644", байты: Data("x".utf8))])
    }
    let до = снимок(1, "старый")
    let после = снимок(2, "новый")
    let шаг = ШагВосстановленияFUMA(идентификатор: "move", до: до, после: после)
    #expect(СверкаВосстановленияFUMA.проверить(шаги: [шаг], квитанции: [],
        намерениеБезКвитанции: nil, наблюдение: до)
        == .совпадениеПереданныхДанных(завершеноШагов: 0, всегоШагов: 1))
    for наблюдение in [до, после] {
        #expect(СверкаВосстановленияFUMA.проверить(шаги: [шаг], квитанции: [],
            намерениеБезКвитанции: "move", наблюдение: наблюдение) == .неизвестныйИсход)
    }
    #expect(СверкаВосстановленияFUMA.проверить(шаги: [шаг], квитанции: ["move"],
        намерениеБезКвитанции: nil, наблюдение: после)
        == .совпадениеПереданныхДанных(завершеноШагов: 1, всегоШагов: 1))
    #expect(СверкаВосстановленияFUMA.проверить(шаги: [шаг], квитанции: ["move"],
        намерениеБезКвитанции: nil, наблюдение: до) == .дрейф)
    #expect(СверкаВосстановленияFUMA.проверить(шаги: [шаг], квитанции: ["другой"],
        намерениеБезКвитанции: nil, наблюдение: после) == .неверныеДанные)
}


import Foundation

/// Общий порядок из требования FUMA; пределы каждой точной модели приходят только из переданного каталога.
/// Шкала нужна для соседства; сам тип не переключает модель и не запускает работу.
public enum СтупеньУсилия: String, CaseIterable, Codable, Sendable {
    case low
    case medium
    case high
    case xhigh
    case max
    case ultra
}

/// Единственный переданный источник точных ID и ступеней; версия схемы и внешнего провайдера независимы.
/// Значение не запрашивает и не удостоверяет метаданные модели.
public struct ВозможностиУсилияМодели: Codable, Equatable, Sendable {
    public let модель: String
    public let ступени: [СтупеньУсилия]
    public let источник: Знание<String>
    public let версияСхемыКаталога: Знание<String>
    public let версияВнешнегоПровайдера: Знание<String>

    public init(модель: String, ступени: [СтупеньУсилия], источник: Знание<String>,
        версияСхемыКаталога: Знание<String>, версияВнешнегоПровайдера: Знание<String>) {
        self.модель = модель
        self.ступени = ступени
        self.источник = источник
        self.версияСхемыКаталога = версияСхемыКаталога
        self.версияВнешнегоПровайдера = версияВнешнегоПровайдера
    }

    public static func найти(
        модель: String,
        каталог: Знание<[ВозможностиУсилияМодели]>
    ) -> Знание<ВозможностиУсилияМодели> {
        guard case .известно(let записи) = каталог,
              !записи.isEmpty,
              Set(записи.map(\.модель)).count == записи.count,
              let запись = записи.first(where: { $0.модель == модель }),
              !модель.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              модель == модель.trimmingCharacters(in: .whitespacesAndNewlines),
              запись.модель == запись.модель.trimmingCharacters(in: .whitespacesAndNewlines),
              !запись.ступени.isEmpty,
              Set(запись.ступени).count == запись.ступени.count,
              запись.ступени == СтупеньУсилия.allCases.filter({ запись.ступени.contains($0) }),
              case .известно(let источник) = запись.источник,
              !источник.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return .неизвестно(причина: "неизвестный или неподтверждённый каталог модели")
        }
        return .известно(запись)
    }
}

/// Запрошенное и переданное наблюдаемое значения хранятся раздельно; значение не удостоверяет удалённую конфигурацию.
public struct КонфигурацияМоделиУсилия: Codable, Equatable, Sendable {
    public let модель: String
    public let усилие: СтупеньУсилия

    public init(модель: String, усилие: СтупеньУсилия) {
        self.модель = модель
        self.усилие = усилие
    }
}

/// Подтверждения и происхождение переданы вызывающим и сами по себе не являются независимой аттестацией.
public struct СвидетельствоПониженияУсилия: Codable, Equatable, Sendable {
    public let устойчивость: Знание<String>
    public let автоматизация: Знание<String>
    public let происхождение: Знание<String>

    public init(устойчивость: Знание<String>, автоматизация: Знание<String>, происхождение: Знание<String>) {
        self.устойчивость = устойчивость
        self.автоматизация = автоматизация
        self.происхождение = происхождение
    }
}

/// Поля инициатора и причины являются переданными данными, а не удостоверением личности или полномочий.
public struct ВходПереходаУсилия: Codable, Equatable, Sendable {
    public let запрошенная: Знание<КонфигурацияМоделиУсилия>
    public let наблюдаемая: Знание<КонфигурацияМоделиУсилия>
    public let каталогМоделей: Знание<[ВозможностиУсилияМодели]>
    public let наблюдениеЗатруднения: Знание<String>
    public let свидетельствоПонижения: СвидетельствоПониженияУсилия
    public let инициатор: Знание<String>
    public let причина: Знание<String>

    public init(запрошенная: Знание<КонфигурацияМоделиУсилия>,
        наблюдаемая: Знание<КонфигурацияМоделиУсилия>,
        каталогМоделей: Знание<[ВозможностиУсилияМодели]> = .неизвестно(причина: "каталог возможностей модели не передан"),
        наблюдениеЗатруднения: Знание<String>, свидетельствоПонижения: СвидетельствоПониженияУсилия,
        инициатор: Знание<String>, причина: Знание<String>) {
        self.запрошенная = запрошенная
        self.наблюдаемая = наблюдаемая
        self.каталогМоделей = каталогМоделей
        self.наблюдениеЗатруднения = наблюдениеЗатруднения
        self.свидетельствоПонижения = свидетельствоПонижения
        self.инициатор = инициатор
        self.причина = причина
    }

    private enum Ключи: String, CodingKey {
        case запрошенная, наблюдаемая, каталогМоделей
        case наблюдениеЗатруднения, свидетельствоПонижения, инициатор, причина
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: Ключи.self)
        запрошенная = try container.decode(Знание<КонфигурацияМоделиУсилия>.self, forKey: .запрошенная)
        наблюдаемая = try container.decode(Знание<КонфигурацияМоделиУсилия>.self, forKey: .наблюдаемая)
        каталогМоделей = try container.decodeIfPresent(Знание<[ВозможностиУсилияМодели]>.self, forKey: .каталогМоделей)
            ?? .неизвестно(причина: "каталог возможностей модели не передан")
        наблюдениеЗатруднения = try container.decode(Знание<String>.self, forKey: .наблюдениеЗатруднения)
        свидетельствоПонижения = try container.decode(СвидетельствоПониженияУсилия.self, forKey: .свидетельствоПонижения)
        инициатор = try container.decode(Знание<String>.self, forKey: .инициатор)
        причина = try container.decode(Знание<String>.self, forKey: .причина)
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: Ключи.self)
        try container.encode(запрошенная, forKey: .запрошенная)
        try container.encode(наблюдаемая, forKey: .наблюдаемая)
        try container.encode(каталогМоделей, forKey: .каталогМоделей)
        try container.encode(наблюдениеЗатруднения, forKey: .наблюдениеЗатруднения)
        try container.encode(свидетельствоПонижения, forKey: .свидетельствоПонижения)
        try container.encode(инициатор, forKey: .инициатор)
        try container.encode(причина, forKey: .причина)
    }
}

public enum РезультатПереходаУсилия: String, Codable, Sendable {
    case безИзменения
    case предложено
}

public struct ЗаписьИсторииУсилия: Codable, Equatable, Sendable {
    public let id: UUID
    public let запрошенная: КонфигурацияМоделиУсилия
    public let наблюдаемая: КонфигурацияМоделиУсилия
    public let результат: РезультатПереходаУсилия
    public let инициатор: String
    public let причина: String
    public let основание: String
    public let наблюдение: String
    public let предыдущая: КонфигурацияМоделиУсилия
    public let предложенная: КонфигурацияМоделиУсилия
    public let наблюдаемоеПосле: Знание<КонфигурацияМоделиУсилия>

    public init(id: UUID, запрошенная: КонфигурацияМоделиУсилия,
        наблюдаемая: КонфигурацияМоделиУсилия, результат: РезультатПереходаУсилия,
        инициатор: String, причина: String, наблюдение: String, основание: String? = nil,
        наблюдаемоеПосле: Знание<КонфигурацияМоделиУсилия> = .неизвестно(причина: "результат предложения не наблюдался")) {
        self.id = id
        self.запрошенная = запрошенная
        self.наблюдаемая = наблюдаемая
        self.результат = результат
        self.инициатор = инициатор
        self.причина = причина
        self.основание = основание ?? наблюдение
        self.наблюдение = наблюдение
        self.предыдущая = наблюдаемая
        self.предложенная = запрошенная
        self.наблюдаемоеПосле = наблюдаемоеПосле
    }

    private enum Ключи: String, CodingKey {
        case id, запрошенная, наблюдаемая, результат, инициатор, причина, основание, наблюдение
        case предыдущая, предложенная, наблюдаемоеПосле
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: Ключи.self)
        id = try container.decode(UUID.self, forKey: .id)
        запрошенная = try container.decode(КонфигурацияМоделиУсилия.self, forKey: .запрошенная)
        наблюдаемая = try container.decode(КонфигурацияМоделиУсилия.self, forKey: .наблюдаемая)
        результат = try container.decode(РезультатПереходаУсилия.self, forKey: .результат)
        инициатор = try container.decode(String.self, forKey: .инициатор)
        причина = try container.decode(String.self, forKey: .причина)
        наблюдение = try container.decode(String.self, forKey: .наблюдение)
        основание = try container.decodeIfPresent(String.self, forKey: .основание) ?? наблюдение
        предыдущая = try container.decodeIfPresent(КонфигурацияМоделиУсилия.self, forKey: .предыдущая) ?? наблюдаемая
        предложенная = try container.decodeIfPresent(КонфигурацияМоделиУсилия.self, forKey: .предложенная) ?? запрошенная
        наблюдаемоеПосле = try container.decodeIfPresent(Знание<КонфигурацияМоделиУсилия>.self, forKey: .наблюдаемоеПосле)
            ?? .неизвестно(причина: "результат предложения не наблюдался")
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: Ключи.self)
        try container.encode(id, forKey: .id)
        try container.encode(запрошенная, forKey: .запрошенная)
        try container.encode(наблюдаемая, forKey: .наблюдаемая)
        try container.encode(результат, forKey: .результат)
        try container.encode(инициатор, forKey: .инициатор)
        try container.encode(причина, forKey: .причина)
        try container.encode(основание, forKey: .основание)
        try container.encode(наблюдение, forKey: .наблюдение)
        try container.encode(предыдущая, forKey: .предыдущая)
        try container.encode(предложенная, forKey: .предложенная)
        try container.encode(наблюдаемоеПосле, forKey: .наблюдаемоеПосле)
    }
}

public enum СостояниеПереходаУсилия: Equatable, Sendable {
    case предложено(КонфигурацияМоделиУсилия)
    case безИзменения
    case неизвестно
}

public struct РешениеПереходаУсилия: Equatable, Sendable {
    public let состояние: СостояниеПереходаУсилия
    public let история: [ЗаписьИсторииУсилия]

    public init(состояние: СостояниеПереходаУсилия, история: [ЗаписьИсторииУсилия]) {
        self.состояние = состояние
        self.история = история
    }
}

/// Для новой задачи берётся Luna Low; переданный прямой выбор человека имеет приоритет, но не удостоверяет личность вызывающего.
public enum ВыборУсилияДляНовойЗадачи {
    public static let конфигурацияПоУмолчанию = КонфигурацияМоделиУсилия(модель: "gpt-6-luna", усилие: .low)

    public static func выбрать(
        каталог: Знание<[ВозможностиУсилияМодели]>,
        прямойВыборЧеловека: КонфигурацияМоделиУсилия? = nil
    )
        -> Знание<КонфигурацияМоделиУсилия> {
        let выбор = прямойВыборЧеловека ?? конфигурацияПоУмолчанию
        guard case .известно(let возможности) = ВозможностиУсилияМодели.найти(модель: выбор.модель, каталог: каталог),
              возможности.ступени.contains(выбор.усилие) else {
            return .неизвестно(причина: "неподдерживаемая ступень для модели")
        }
        return .известно(выбор)
    }
}

/// Чистая проекция: сохраняет переданную историю и только добавляет запись при определённом результате.
public enum ПереходУсилия {
    public static func предложить(_ вход: ВходПереходаУсилия,
        история: [ЗаписьИсторииУсилия], idЗаписи: UUID = UUID()) -> РешениеПереходаУсилия {
        func неизвестно() -> РешениеПереходаУсилия {
            .init(состояние: .неизвестно, история: история)
        }
        guard case .известно(let запрошенная) = вход.запрошенная,
              case .известно(let наблюдаемая) = вход.наблюдаемая,
              case .известно(let возможности) = ВозможностиУсилияМодели.найти(
                модель: запрошенная.модель, каталог: вход.каталогМоделей),
              запрошенная.модель == наблюдаемая.модель,
              возможности.ступени.contains(наблюдаемая.усилие),
              возможности.ступени.contains(запрошенная.усилие),
              case .известно(let инициатор) = вход.инициатор,
              case .известно(let причина) = вход.причина,
              !инициатор.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              !причина.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return неизвестно()
        }

        let ступени = СтупеньУсилия.allCases
        guard let индексНаблюдаемой = ступени.firstIndex(of: наблюдаемая.усилие),
              let индексЗапрошенной = ступени.firstIndex(of: запрошенная.усилие) else {
            return неизвестно()
        }

        let направление: (РезультатПереходаУсилия, String)?
        if индексЗапрошенной == индексНаблюдаемой {
            направление = (.безИзменения, "запрошенная ступень совпадает с переданной наблюдаемой ступенью")
        } else if индексЗапрошенной == индексНаблюдаемой + 1,
                  case .известно(let затруднение) = вход.наблюдениеЗатруднения,
                  !затруднение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            направление = (.предложено, затруднение)
        } else if индексНаблюдаемой == индексЗапрошенной + 1,
                  case .известно(let устойчивость) = вход.свидетельствоПонижения.устойчивость,
                  case .известно(let автоматизация) = вход.свидетельствоПонижения.автоматизация,
                  case .известно(let происхождение) = вход.свидетельствоПонижения.происхождение,
                  !устойчивость.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  !автоматизация.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  !происхождение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            направление = (.предложено, "устойчивость: \(устойчивость); автоматизация: \(автоматизация); происхождение: \(происхождение)")
        } else {
            направление = nil
        }
        guard let (результат, наблюдение) = направление else { return неизвестно() }

        let наблюдаемоеПосле: Знание<КонфигурацияМоделиУсилия> =
            .неизвестно(причина: "после предложения отдельное наблюдение не передавалось")
        let запись = ЗаписьИсторииУсилия(id: idЗаписи, запрошенная: запрошенная,
            наблюдаемая: наблюдаемая, результат: результат, инициатор: инициатор,
            причина: причина, наблюдение: наблюдение, основание: наблюдение, наблюдаемоеПосле: наблюдаемоеПосле)
        let состояние: СостояниеПереходаУсилия = результат == .безИзменения
            ? .безИзменения : .предложено(запрошенная)
        return .init(состояние: состояние, история: история + [запись])
    }
}

import Foundation

/// Шкала усилия для предложения конфигурации; сам тип не переключает модель и не запускает работу.
public enum СтупеньУсилия: String, CaseIterable, Codable, Sendable {
    case low
    case medium
    case high
    case xhigh
    case max
}

/// Запрошенное и переданное наблюдаемое значения хранятся раздельно; значение не удостоверяет удалённую конфигурацию.
public struct КонфигурацияМоделиУсилия: Codable, Equatable, Sendable {
    public let модель: String
    public let усилие: СтупеньУсилия

    public init(модель: String, усилие: СтупеньУсилия) {
        self.модель = модель
        self.усилие = усилие
    }
}

/// Подтверждения и происхождение переданы вызывающим и сами по себе не являются независимой аттестацией.
public struct СвидетельствоПониженияУсилия: Codable, Equatable, Sendable {
    public let устойчивость: Знание<String>
    public let автоматизация: Знание<String>
    public let происхождение: Знание<String>

    public init(устойчивость: Знание<String>, автоматизация: Знание<String>, происхождение: Знание<String>) {
        self.устойчивость = устойчивость
        self.автоматизация = автоматизация
        self.происхождение = происхождение
    }
}

/// Поля инициатора и причины являются переданными данными, а не удостоверением личности или полномочий.
public struct ВходПереходаУсилия: Codable, Equatable, Sendable {
    public let запрошенная: Знание<КонфигурацияМоделиУсилия>
    public let наблюдаемая: Знание<КонфигурацияМоделиУсилия>
    public let поддерживаемыеСтупени: Знание<[СтупеньУсилия]>
    public let наблюдениеЗатруднения: Знание<String>
    public let свидетельствоПонижения: СвидетельствоПониженияУсилия
    public let инициатор: Знание<String>
    public let причина: Знание<String>

    public init(запрошенная: Знание<КонфигурацияМоделиУсилия>,
        наблюдаемая: Знание<КонфигурацияМоделиУсилия>,
        поддерживаемыеСтупени: Знание<[СтупеньУсилия]>,
        наблюдениеЗатруднения: Знание<String>, свидетельствоПонижения: СвидетельствоПониженияУсилия,
        инициатор: Знание<String>, причина: Знание<String>) {
        self.запрошенная = запрошенная
        self.наблюдаемая = наблюдаемая
        self.поддерживаемыеСтупени = поддерживаемыеСтупени
        self.наблюдениеЗатруднения = наблюдениеЗатруднения
        self.свидетельствоПонижения = свидетельствоПонижения
        self.инициатор = инициатор
        self.причина = причина
    }
}

public enum РезультатПереходаУсилия: String, Codable, Sendable {
    case безИзменения
    case предложено
}

public struct ЗаписьИсторииУсилия: Codable, Equatable, Sendable {
    public let id: UUID
    public let запрошенная: КонфигурацияМоделиУсилия
    public let наблюдаемая: КонфигурацияМоделиУсилия
    public let результат: РезультатПереходаУсилия
    public let инициатор: String
    public let причина: String
    public let наблюдение: String

    public init(id: UUID, запрошенная: КонфигурацияМоделиУсилия,
        наблюдаемая: КонфигурацияМоделиУсилия, результат: РезультатПереходаУсилия,
        инициатор: String, причина: String, наблюдение: String) {
        self.id = id
        self.запрошенная = запрошенная
        self.наблюдаемая = наблюдаемая
        self.результат = результат
        self.инициатор = инициатор
        self.причина = причина
        self.наблюдение = наблюдение
    }
}

public enum СостояниеПереходаУсилия: Equatable, Sendable {
    case предложено(КонфигурацияМоделиУсилия)
    case безИзменения
    case неизвестно
}

public struct РешениеПереходаУсилия: Equatable, Sendable {
    public let состояние: СостояниеПереходаУсилия
    public let история: [ЗаписьИсторииУсилия]

    public init(состояние: СостояниеПереходаУсилия, история: [ЗаписьИсторииУсилия]) {
        self.состояние = состояние
        self.история = история
    }
}

/// Чистая проекция: сохраняет переданную историю и только добавляет запись при определённом результате.
public enum ПереходУсилия {
    public static func предложить(_ вход: ВходПереходаУсилия,
        история: [ЗаписьИсторииУсилия], idЗаписи: UUID = UUID()) -> РешениеПереходаУсилия {
        func неизвестно() -> РешениеПереходаУсилия {
            .init(состояние: .неизвестно, история: история)
        }
        guard case .известно(let запрошенная) = вход.запрошенная,
              case .известно(let наблюдаемая) = вход.наблюдаемая,
              case .известно(let поддерживаемые) = вход.поддерживаемыеСтупени,
              запрошенная.модель == "gpt-6-luna", наблюдаемая.модель == "gpt-6-luna",
              запрошенная.модель == наблюдаемая.модель,
              !запрошенная.модель.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              Set(поддерживаемые).count == поддерживаемые.count,
              поддерживаемые.contains(наблюдаемая.усилие),
              поддерживаемые.contains(запрошенная.усилие),
              case .известно(let инициатор) = вход.инициатор,
              case .известно(let причина) = вход.причина,
              !инициатор.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              !причина.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return неизвестно()
        }

        let ступени = СтупеньУсилия.allCases
        guard let индексНаблюдаемой = ступени.firstIndex(of: наблюдаемая.усилие),
              let индексЗапрошенной = ступени.firstIndex(of: запрошенная.усилие) else {
            return неизвестно()
        }

        let направление: (РезультатПереходаУсилия, String)?
        if индексЗапрошенной == индексНаблюдаемой {
            направление = (.безИзменения, "")
        } else if индексЗапрошенной == индексНаблюдаемой + 1,
                  case .известно(let затруднение) = вход.наблюдениеЗатруднения,
                  !затруднение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            направление = (.предложено, затруднение)
        } else if индексНаблюдаемой == индексЗапрошенной + 1,
                  case .известно(let устойчивость) = вход.свидетельствоПонижения.устойчивость,
                  case .известно(let автоматизация) = вход.свидетельствоПонижения.автоматизация,
                  case .известно(let происхождение) = вход.свидетельствоПонижения.происхождение,
                  !устойчивость.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  !автоматизация.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  !происхождение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            направление = (.предложено, "устойчивость: \(устойчивость); автоматизация: \(автоматизация); происхождение: \(происхождение)")
        } else {
            направление = nil
        }
        guard let (результат, наблюдение) = направление else { return неизвестно() }

        let запись = ЗаписьИсторииУсилия(id: idЗаписи, запрошенная: запрошенная,
            наблюдаемая: наблюдаемая, результат: результат, инициатор: инициатор,
            причина: причина, наблюдение: наблюдение)
        let состояние: СостояниеПереходаУсилия = результат == .безИзменения
            ? .безИзменения : .предложено(запрошенная)
        return .init(состояние: состояние, история: история + [запись])
    }
}

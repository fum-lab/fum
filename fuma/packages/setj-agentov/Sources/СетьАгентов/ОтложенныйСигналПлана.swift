import Foundation

/// Заявленный статус одной попытки основного плана. Статус сам по себе не
/// удостоверяет внешний эффект: адаптер только переносит переданные DTO.
public enum СтатусПопыткиРаботыПлана: String, Codable, Sendable {
    case выполняется
    case завершена
    case ошибка
    case неизвестен
}

public struct ПопыткаРаботыСигнала: Codable, Equatable, Sendable {
    public let id: UUID
    public let исход: Знание<СтатусПопыткиРаботыПлана>

    public init(id: UUID, исход: Знание<СтатусПопыткиРаботыПлана>) {
        self.id = id
        self.исход = исход
    }
}

/// План содержит только следующий уже разрешённый шаг и идентичность
/// незавершённой попытки. Входящий сигнал не переписывает эти поля.
public struct ПланРаботыСигнала: Codable, Equatable, Sendable {
    public let id: UUID
    public let следующийРазрешённыйШаг: Знание<String>
    public let попытка: ПопыткаРаботыСигнала

    public init(id: UUID, следующийРазрешённыйШаг: Знание<String>, попытка: ПопыткаРаботыСигнала) {
        self.id = id
        self.следующийРазрешённыйШаг = следующийРазрешённыйШаг
        self.попытка = попытка
    }
}

public struct СигналРаботыПлана: Codable, Equatable, Sendable {
    public let id: UUID
    public let данные: Data

    public init(id: UUID, данные: Data) {
        self.id = id
        self.данные = данные
    }
}

public enum СостояниеОтложенногоСигнала: String, Codable, Sendable {
    case ожидаетИсхода
    case предложенКРассмотрению
    case неизвестныйИсход
}

public struct ЗаписьОтложенногоСигнала: Codable, Equatable, Sendable {
    public let сигнал: СигналРаботыПлана
    public let состояние: СостояниеОтложенногоСигнала

    public init(сигнал: СигналРаботыПлана, состояние: СостояниеОтложенногоСигнала = .ожидаетИсхода) {
        self.сигнал = сигнал
        self.состояние = состояние
    }
}

public enum ДоступностьСледующегоШагаПлана: String, Codable, Sendable {
    case разрешён
    case запрещён
}

public struct ИсходПопыткиСигналаПлана: Codable, Equatable, Sendable {
    public let id: UUID
    public let попытка: UUID
    public let статус: СтатусПопыткиРаботыПлана
    public let доступностьСледующегоШага: Знание<ДоступностьСледующегоШагаПлана>

    public init(id: UUID, попытка: UUID, статус: СтатусПопыткиРаботыПлана,
                доступностьСледующегоШага: Знание<ДоступностьСледующегоШагаПлана>) {
        self.id = id
        self.попытка = попытка
        self.статус = статус
        self.доступностьСледующегоШага = доступностьСледующегоШага
    }
}

public enum СтатусОбработкиСигналаПлана: String, Codable, Sendable {
    case обработан
    case неизвестно
}

public struct ПодтверждениеОбработкиСигналаПлана: Codable, Equatable, Sendable {
    public let id: UUID
    public let сигнал: UUID
    public let статус: СтатусОбработкиСигналаПлана

    public init(id: UUID, сигнал: UUID, статус: СтатусОбработкиСигналаПлана) {
        self.id = id
        self.сигнал = сигнал
        self.статус = статус
    }
}

/// Позднее наблюдение источника об уже переданном сигнале. Это заявленное
/// свидетельство исхода, не команда на повторную обработку.
public struct НаблюдениеОбработкиСигналаПлана: Codable, Equatable, Sendable {
    public let id: UUID
    public let сигнал: UUID
    public let попытка: UUID
    public let происхождение: Знание<String>
    public let результат: Знание<СтатусОбработкиСигналаПлана>

    public init(id: UUID, сигнал: UUID, попытка: UUID, происхождение: Знание<String>,
                результат: Знание<СтатусОбработкиСигналаПлана>) {
        self.id = id
        self.сигнал = сигнал
        self.попытка = попытка
        self.происхождение = происхождение
        self.результат = результат
    }
}

public struct СостояниеСигналовПлана: Codable, Equatable, Sendable {
    public let план: ПланРаботыСигнала
    public let сигналы: [ЗаписьОтложенногоСигнала]
    public let исход: ИсходПопыткиСигналаПлана?
    public let подтверждения: [ПодтверждениеОбработкиСигналаПлана]
    public let наблюденияОбработки: [НаблюдениеОбработкиСигналаПлана]

    public init(план: ПланРаботыСигнала, сигналы: [ЗаписьОтложенногоСигнала] = [],
                исход: ИсходПопыткиСигналаПлана? = nil,
                подтверждения: [ПодтверждениеОбработкиСигналаПлана] = [],
                наблюденияОбработки: [НаблюдениеОбработкиСигналаПлана] = []) {
        self.план = план
        self.сигналы = сигналы
        self.исход = исход
        self.подтверждения = подтверждения
        self.наблюденияОбработки = наблюденияОбработки
    }
}

public enum СобытиеОтложенногоСигналаПлана: Codable, Equatable, Sendable {
    case сигнал(СигналРаботыПлана)
    case исход(ИсходПопыткиСигналаПлана)
    case подтверждение(ПодтверждениеОбработкиСигналаПлана)
    case наблюдениеОбработки(НаблюдениеОбработкиСигналаПлана)
}

public enum ПереходОтложенногоСигналаПлана: Equatable, Sendable {
    case отложено(СостояниеСигналовПлана)
    case исходСохранён(СостояниеСигналовПлана)
    case обработкаСохранена(СостояниеСигналовПлана)
    case продолжениеНеРазрешено(СостояниеСигналовПлана)
    /// Предложение ранее сохранённого шага с сигналом; это не команда и не runtime-вызов.
    case продолжить(шаг: String, сигнал: СигналРаботыПлана, состояние: СостояниеСигналовПлана)
    case безИзменений(СостояниеСигналовПлана)
    case неизвестно(причина: String, состояние: СостояниеСигналовПлана)
}

/// Чистая проекция DTO. Не запускает попытку, не применяет сигнал и не
/// связывается с runtime. Повтор одного ID идемпотентен; конфликт даёт UNKNOWN.
public enum ОтложенныйСигналПлана {
    public static func сократить(
        _ состояние: СостояниеСигналовПлана,
        событие: СобытиеОтложенногоСигналаПлана
    ) -> ПереходОтложенногоСигналаПлана {
        if let причина = ошибкаСостояния(состояние) {
            return .неизвестно(причина: причина, состояние: состояние)
        }
        switch событие {
        case .сигнал(let сигнал):
            if let прежняя = состояние.сигналы.first(where: { $0.сигнал.id == сигнал.id }) {
                guard прежняя.сигнал == сигнал else {
                    return .неизвестно(причина: "конфликт-ID-сигнала", состояние: состояние)
                }
                return .безИзменений(состояние)
            }
            let новое = СостояниеСигналовПлана(план: состояние.план,
                сигналы: состояние.сигналы + [ЗаписьОтложенногоСигнала(сигнал: сигнал)],
                исход: состояние.исход, подтверждения: состояние.подтверждения,
                наблюденияОбработки: состояние.наблюденияОбработки)
            if let исход = новое.исход {
                return предложитьПродолжение(для: исход, в: новое)
            }
            return .отложено(новое)

        case .исход(let исход):
            guard исход.попытка == состояние.план.попытка.id else {
                return .неизвестно(причина: "исход-другой-попытки", состояние: состояние)
            }
            if let прежний = состояние.исход {
                guard прежний == исход else {
                    return .неизвестно(причина: "конфликт-исхода-попытки", состояние: состояние)
                }
                return .безИзменений(состояние)
            }
            guard исход.статус == .завершена || исход.статус == .ошибка else {
                return .отложено(состояние)
            }
            guard case .известно(.выполняется) = состояние.план.попытка.исход else {
                return .неизвестно(причина: "попытка-не-подтверждена-как-активная", состояние: состояние)
            }

            let попытка = ПопыткаРаботыСигнала(id: состояние.план.попытка.id, исход: .известно(исход.статус))
            let план = ПланРаботыСигнала(id: состояние.план.id,
                следующийРазрешённыйШаг: состояние.план.следующийРазрешённыйШаг, попытка: попытка)
            let новое = СостояниеСигналовПлана(план: план, сигналы: состояние.сигналы,
                исход: исход, подтверждения: состояние.подтверждения,
                наблюденияОбработки: состояние.наблюденияОбработки)
            guard новое.сигналы.contains(where: { $0.состояние == .ожидаетИсхода }) else {
                return .исходСохранён(новое)
            }
            return предложитьПродолжение(для: исход, в: новое)

        case .подтверждение(let подтверждение):
            if let прежнее = состояние.подтверждения.first(where: { $0.id == подтверждение.id }) {
                guard прежнее == подтверждение else {
                    return .неизвестно(причина: "конфликт-ID-подтверждения", состояние: состояние)
                }
                return .безИзменений(состояние)
            }
            guard let первый = состояние.сигналы.first,
                  первый.состояние == .предложенКРассмотрению,
                  первый.сигнал.id == подтверждение.сигнал else {
                return .неизвестно(причина: "подтверждение-не-совпадает-с-головой-FIFO", состояние: состояние)
            }
            let история = состояние.подтверждения + [подтверждение]
            if подтверждение.статус == .неизвестно {
                var сигналы = состояние.сигналы
                сигналы[0] = ЗаписьОтложенногоСигнала(сигнал: первый.сигнал, состояние: .неизвестныйИсход)
                let новое = СостояниеСигналовПлана(план: состояние.план, сигналы: сигналы,
                    исход: состояние.исход, подтверждения: история,
                    наблюденияОбработки: состояние.наблюденияОбработки)
                return .неизвестно(причина: "исход-обработки-сигнала-неизвестен", состояние: новое)
            }
            let оставшиеся = Array(состояние.сигналы.dropFirst())
            let новое = СостояниеСигналовПлана(план: состояние.план, сигналы: оставшиеся,
                исход: состояние.исход, подтверждения: история,
                наблюденияОбработки: состояние.наблюденияОбработки)
            if let исход = новое.исход, оставшиеся.contains(where: { $0.состояние == .ожидаетИсхода }) {
                let переход = предложитьПродолжение(для: исход, в: новое)
                switch переход {
                case .продолжить, .неизвестно, .продолжениеНеРазрешено: return переход
                default: break
                }
            }
            return .обработкаСохранена(новое)

        case .наблюдениеОбработки(let наблюдение):
            if let прежнее = состояние.наблюденияОбработки.first(where: { $0.id == наблюдение.id }) {
                guard прежнее == наблюдение else {
                    return .неизвестно(причина: "конфликт-ID-наблюдения", состояние: состояние)
                }
                return .безИзменений(состояние)
            }
            guard !состояние.наблюденияОбработки.contains(where: { $0.сигнал == наблюдение.сигнал }) else {
                return .неизвестно(причина: "сигнал-уже-разрешён-наблюдением", состояние: состояние)
            }
            guard let первый = состояние.сигналы.first,
                  первый.состояние == .неизвестныйИсход,
                  первый.сигнал.id == наблюдение.сигнал,
                  let исход = состояние.исход,
                  наблюдение.попытка == состояние.план.попытка.id,
                  наблюдение.попытка == исход.попытка,
                  состояние.подтверждения.contains(where: {
                      $0.сигнал == наблюдение.сигнал && $0.статус == .неизвестно
                  }),
                  case .известно(.обработан) = наблюдение.результат,
                  case .известно(let происхождение) = наблюдение.происхождение,
                  !происхождение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                return .неизвестно(причина: "нет-согласованного-наблюдения-исхода", состояние: состояние)
            }
            let оставшиеся = Array(состояние.сигналы.dropFirst())
            let история = состояние.наблюденияОбработки + [наблюдение]
            let новое = СостояниеСигналовПлана(план: состояние.план, сигналы: оставшиеся,
                исход: состояние.исход, подтверждения: состояние.подтверждения,
                наблюденияОбработки: история)
            if оставшиеся.contains(where: { $0.состояние == .ожидаетИсхода }), let исход = новое.исход {
                let переход = предложитьПродолжение(для: исход, в: новое)
                if case .продолжить = переход { return переход }
                if case .неизвестно = переход { return переход }
                if case .продолжениеНеРазрешено = переход { return переход }
            }
            return .обработкаСохранена(новое)
        }
    }

    private static func предложитьПродолжение(
        для исход: ИсходПопыткиСигналаПлана,
        в состояние: СостояниеСигналовПлана
    ) -> ПереходОтложенногоСигналаПлана {
        guard исход.статус == .завершена || исход.статус == .ошибка else {
            return .отложено(состояние)
        }
        switch исход.доступностьСледующегоШага {
        case .известно(.разрешён): break
        case .известно(.запрещён): return .продолжениеНеРазрешено(состояние)
        case .неизвестно(let причина):
            return .неизвестно(причина: "допустимость-шага-неизвестна:\(причина)", состояние: состояние)
        }
        guard !состояние.сигналы.contains(where: {
            $0.состояние == .предложенКРассмотрению || $0.состояние == .неизвестныйИсход
        }),
              let индекс = состояние.сигналы.firstIndex(where: { $0.состояние == .ожидаетИсхода }) else {
            return .отложено(состояние)
        }
        guard case .известно(let шаг) = состояние.план.следующийРазрешённыйШаг,
              !шаг.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return .неизвестно(причина: "нет-известного-разрешённого-следующего-шага", состояние: состояние)
        }
        var сигналы = состояние.сигналы
        let запись = сигналы[индекс]
        сигналы[индекс] = ЗаписьОтложенногоСигнала(сигнал: запись.сигнал, состояние: .предложенКРассмотрению)
        let новое = СостояниеСигналовПлана(план: состояние.план, сигналы: сигналы,
            исход: состояние.исход, подтверждения: состояние.подтверждения,
            наблюденияОбработки: состояние.наблюденияОбработки)
        return .продолжить(шаг: шаг, сигнал: запись.сигнал, состояние: новое)
    }

    private static func ошибкаСостояния(_ состояние: СостояниеСигналовПлана) -> String? {
        let идентификаторы = состояние.сигналы.map { $0.сигнал.id }
        guard Set(идентификаторы).count == идентификаторы.count else { return "повтор-ID-сигнала-в-состоянии" }
        guard состояние.сигналы.filter({ $0.состояние == .предложенКРассмотрению }).count <= 1 else {
            return "несколько-предложенных-сигналов"
        }
        let идентификаторыПодтверждений = состояние.подтверждения.map(\.id)
        guard Set(идентификаторыПодтверждений).count == идентификаторыПодтверждений.count else {
            return "повтор-ID-подтверждения"
        }
        let подтверждённыеСигналы = состояние.подтверждения.map(\.сигнал)
        guard Set(подтверждённыеСигналы).count == подтверждённыеСигналы.count else {
            return "повторная-обработка-сигнала"
        }
        for подтверждение in состояние.подтверждения {
            let сохранённыйСигнал = состояние.сигналы.first(where: { $0.сигнал.id == подтверждение.сигнал })
            if подтверждение.статус == .обработан, сохранённыйСигнал != nil {
                return "обработанный-сигнал-остался-в-очереди"
            }
            if подтверждение.статус == .неизвестно,
               сохранённыйСигнал?.состояние != .неизвестныйИсход,
               !состояние.наблюденияОбработки.contains(where: { $0.сигнал == подтверждение.сигнал }) {
                return "UNKNOWN-подтверждение-без-сигнала-в-очереди"
            }
        }
        let идентификаторыНаблюдений = состояние.наблюденияОбработки.map(\.id)
        let сигналыНаблюдений = состояние.наблюденияОбработки.map(\.сигнал)
        guard Set(идентификаторыНаблюдений).count == идентификаторыНаблюдений.count,
              Set(сигналыНаблюдений).count == сигналыНаблюдений.count else {
            return "повтор-ID-наблюдения-обработки"
        }
        for наблюдение in состояние.наблюденияОбработки {
            guard наблюдение.попытка == состояние.план.попытка.id,
                  состояние.подтверждения.contains(where: {
                      $0.сигнал == наблюдение.сигнал && $0.статус == .неизвестно
                  }),
                  !состояние.сигналы.contains(where: { $0.сигнал.id == наблюдение.сигнал }),
                  case .известно(.обработан) = наблюдение.результат,
                  case .известно(let происхождение) = наблюдение.происхождение,
                  !происхождение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                return "несогласованное-наблюдение-обработки"
            }
        }
        if состояние.сигналы.contains(where: { $0.состояние == .предложенКРассмотрению }), состояние.исход == nil {
            return "предложение-без-терминального-исхода"
        }
        if состояние.сигналы.contains(where: { $0.состояние == .неизвестныйИсход }),
           состояние.подтверждения.last?.статус != .неизвестно {
            return "неизвестный-исход-сигнала-без-подтверждения"
        }
        guard let исход = состояние.исход else {
            if case .известно(.завершена) = состояние.план.попытка.исход { return "нет-ID-исхода" }
            if case .известно(.ошибка) = состояние.план.попытка.исход { return "нет-ID-исхода" }
            return nil
        }
        guard исход.попытка == состояние.план.попытка.id,
              состояние.план.попытка.исход == .известно(исход.статус),
              (исход.статус == .завершена || исход.статус == .ошибка) else {
            return "несогласованный-исход-в-состоянии"
        }
        return nil
    }
}

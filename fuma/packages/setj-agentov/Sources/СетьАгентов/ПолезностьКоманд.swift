import Foundation

public enum ПричинаНеизвестнойПолезности: Equatable, Sendable {
    case неверноеОкно, нетДанных, превышенПредел, повторID, внеОкна
    case нетТерминала, нетЗаявленнойКвитанции, нетПолезности, отрицательнаяПолезность
    case нетЗатрат, переполнение
}

/// Только сумма заявленных счётчиков за переданное окно; не подтверждает полезность или принятие.
public struct ЗаявленнаяСводкаКоманд: Equatable, Sendable {
    public let команд: Int
    public let заявленныхРезультатов: UInt64
    public let заявленныхЗатрат: UInt64

    /// Точная дробь без округления; нулевые затраты не дают отношения.
    public var отношение: (числитель: UInt64, знаменатель: UInt64)? {
        guard заявленныхЗатрат > 0 else { return nil }
        return (заявленныхРезультатов, заявленныхЗатрат)
    }
}

public enum РезультатСводкиКоманд: Equatable, Sendable {
    case заявлено(ЗаявленнаяСводкаКоманд)
    case неизвестно(ПричинаНеизвестнойПолезности)
}

/// Чистое сведение данных. Ни полнота окна, ни источник DTO, ни фактическое
/// принятие результатов не устанавливаются; использовать как authority нельзя.
public enum ПолезностьКоманд {
    public static func свести(исходы: [ИсходКоманды], начало: Date, конец: Date) -> РезультатСводкиКоманд {
        guard начало.timeIntervalSinceReferenceDate.isFinite, конец.timeIntervalSinceReferenceDate.isFinite,
              начало < конец else { return .неизвестно(.неверноеОкно) }
        guard !исходы.isEmpty else { return .неизвестно(.нетДанных) }
        guard исходы.count <= 2048 else { return .неизвестно(.превышенПредел) }
        var идентификаторы: Set<UUID> = []
        var результаты: UInt64 = 0
        var затраты: UInt64 = 0
        for исход in исходы {
            guard идентификаторы.insert(исход.idКоманды).inserted else { return .неизвестно(.повторID) }
            guard исход.наблюдалосьВ.timeIntervalSinceReferenceDate.isFinite,
                  исход.наблюдалосьВ >= начало, исход.наблюдалосьВ < конец else { return .неизвестно(.внеОкна) }
            guard исход.статус == .completed || исход.статус == .failed else { return .неизвестно(.нетТерминала) }
            guard case .известно(let квитанция) = исход.свидетельствоИлиКвитанция,
                  !квитанция.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return .неизвестно(.нетЗаявленнойКвитанции) }
            guard case .известно(let полезные) = исход.полезныеРезультаты else { return .неизвестно(.нетПолезности) }
            guard полезные >= 0 else { return .неизвестно(.отрицательнаяПолезность) }
            guard case .известно(let расход) = исход.затратыЕдиниц else { return .неизвестно(.нетЗатрат) }
            let (новыеРезультаты, переполнениеРезультатов) = результаты.addingReportingOverflow(UInt64(полезные))
            let (новыеЗатраты, переполнениеЗатрат) = затраты.addingReportingOverflow(расход)
            guard !переполнениеРезультатов, !переполнениеЗатрат else { return .неизвестно(.переполнение) }
            результаты = новыеРезультаты
            затраты = новыеЗатраты
        }
        return .заявлено(.init(команд: исходы.count, заявленныхРезультатов: результаты, заявленныхЗатрат: затраты))
    }
}

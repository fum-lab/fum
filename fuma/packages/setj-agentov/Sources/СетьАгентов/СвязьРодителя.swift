import Foundation

/// Идентичность относится к одному поколению одного блокера.
public struct КлючСвязиРодителя: Hashable, Sendable {
    public let родитель: UUID
    public let ребёнок: UUID
    public let поручение: UUID
    public let блокер: UUID
    public let поколение: UInt64
    public let адресатПробуждения: UUID
    public let областьПробуждения: UUID

    public init(родитель: UUID, ребёнок: UUID, поручение: UUID, блокер: UUID, поколение: UInt64,
                адресатПробуждения: UUID, областьПробуждения: UUID) {
        self.родитель = родитель
        self.ребёнок = ребёнок
        self.поручение = поручение
        self.блокер = блокер
        self.поколение = поколение
        self.адресатПробуждения = адресатПробуждения
        self.областьПробуждения = областьПробуждения
    }
}

/// Исходы здесь заявлены входом и не удостоверяют доставку или реальный эффект.
public enum ВидСобытияСвязиРодителя: Equatable, Sendable {
    case блокер
    case намерениеУведомления
    case заявленаДоставка
    case исходДоставкиНеизвестен
    case заявленоОжидание
    case снятиеБлокера
    case намерениеПробуждения
    case заявленоПробуждение
    case исходПробужденияНеизвестен
}

public struct СобытиеСвязиРодителя: Equatable, Sendable {
    public let id: UUID
    public let ключ: КлючСвязиРодителя
    public let вид: ВидСобытияСвязиРодителя
    public let причина: UUID?
    public let основания: [UUID]
    /// Заявленные байты; сам тип не связывает их с декодированными полями.
    public let исходныеБайты: Data

    public init(id: UUID, ключ: КлючСвязиРодителя, вид: ВидСобытияСвязиРодителя,
                причина: UUID?, основания: [UUID] = [], исходныеБайты: Data) {
        self.id = id
        self.ключ = ключ
        self.вид = вид
        self.причина = причина
        self.основания = основания
        self.исходныеБайты = исходныеБайты
    }
}

public enum ПроекцияСвязиРодителя: Equatable, Sendable {
    case предложитьУведомление
    case предложитьПробуждение
    case ожидать
    case заявленоЗавершение
    case неизвестно
}

public enum СогласованностьИсходаУзла: Equatable, Sendable {
    case заявленныеДанныеСогласованы
    case неизвестно
}

/// Чистая проекция переданных событий: не отправляет, не пробуждает и не выдаёт допуск.
public enum СвязьРодителя {
    public static func проекция(ключ: КлючСвязиРодителя, события: [СобытиеСвязиРодителя]) -> ПроекцияСвязиРодителя {
        guard события.count <= 2048 else { return .неизвестно }
        let отбор = события.filter { событие in
            событие.ключ == ключ || (событие.ключ.адресатПробуждения == ключ.адресатПробуждения &&
                (событие.вид == .намерениеПробуждения || событие.вид == .заявленоПробуждение || событие.вид == .исходПробужденияНеизвестен))
        }
        let адресныеID = Set(отбор.map(\.id))
        let область = события.filter { адресныеID.contains($0.id) }
        var уникальные: [UUID: СобытиеСвязиРодителя] = [:]
        var общийРазмер = 0
        for событие in область {
            guard !событие.исходныеБайты.isEmpty, событие.исходныеБайты.count <= 65_536, событие.основания.count <= 2,
                  событие.исходныеБайты.count <= 4_194_304 - общийРазмер else { return .неизвестно }
            общийРазмер += событие.исходныеБайты.count
            if let прежнее = уникальные[событие.id], прежнее != событие { return .неизвестно }
            уникальные[событие.id] = событие
        }
        let выбранные = уникальные.values.filter { $0.ключ == ключ }
        func найти(_ вид: ВидСобытияСвязиРодителя) -> [СобытиеСвязиРодителя] {
            выбранные.filter { $0.вид == вид }
        }
        let блокеры = найти(.блокер)
        guard блокеры.count == 1, let блокер = блокеры.first, блокер.причина == nil else { return .неизвестно }
        let уведомления = найти(.намерениеУведомления)
        let доставки = найти(.заявленаДоставка)
        let неизвестныеДоставки = найти(.исходДоставкиНеизвестен)
        let ожидания = найти(.заявленоОжидание)
        let снятия = найти(.снятиеБлокера)
        let пробуждения = найти(.намерениеПробуждения)
        let исходы = найти(.заявленоПробуждение)
        let неизвестныеИсходы = найти(.исходПробужденияНеизвестен)
        guard уведомления.count <= 1, доставки.count <= 1, неизвестныеДоставки.count <= 1, ожидания.count <= 1,
              снятия.count <= 1, пробуждения.count <= 1, исходы.count <= 1,
              неизвестныеИсходы.count <= 1,
              доставки.isEmpty || неизвестныеДоставки.isEmpty,
              исходы.isEmpty || неизвестныеИсходы.isEmpty,
              уведомления.allSatisfy({ $0.причина == блокер.id }),
              снятия.allSatisfy({ $0.причина == блокер.id }),
              ожидания.allSatisfy({ $0.причина == блокер.id }) else { return .неизвестно }
        guard let уведомление = уведомления.first else {
            return доставки.isEmpty && неизвестныеДоставки.isEmpty && снятия.isEmpty && пробуждения.isEmpty && исходы.isEmpty && неизвестныеИсходы.isEmpty
                ? .предложитьУведомление : .неизвестно
        }
        guard доставки.allSatisfy({ $0.причина == уведомление.id }),
              неизвестныеДоставки.allSatisfy({ $0.причина == уведомление.id }) else { return .неизвестно }
        guard let доставка = доставки.first else {
            if !неизвестныеДоставки.isEmpty { return .неизвестно }
            return пробуждения.isEmpty && исходы.isEmpty && неизвестныеИсходы.isEmpty ? .ожидать : .неизвестно
        }
        guard let снятие = снятия.first else { return пробуждения.isEmpty && исходы.isEmpty && неизвестныеИсходы.isEmpty ? .ожидать : .неизвестно }
        guard let ожидание = ожидания.first else { return пробуждения.isEmpty && исходы.isEmpty && неизвестныеИсходы.isEmpty ? .ожидать : .неизвестно }
        guard снятие.основания == [доставка.id, ожидание.id] else { return .неизвестно }
        if уникальные.values.contains(where: { $0.ключ != ключ && $0.вид == .исходПробужденияНеизвестен }) { return .неизвестно }
        // Заявленный terminal сам по себе не удостоверяет завершение прежнего wake.
        guard !уникальные.values.contains(where: { $0.ключ != ключ &&
            ($0.вид == .намерениеПробуждения || $0.вид == .заявленоПробуждение || $0.вид == .исходПробужденияНеизвестен) }) else { return .неизвестно }
        guard пробуждения.allSatisfy({ $0.причина == снятие.id && $0.основания == [доставка.id, ожидание.id] }) else { return .неизвестно }
        guard let пробуждение = пробуждения.first else {
            return исходы.isEmpty && неизвестныеИсходы.isEmpty ? .предложитьПробуждение : .неизвестно
        }
        guard исходы.allSatisfy({ $0.причина == пробуждение.id }),
              неизвестныеИсходы.allSatisfy({ $0.причина == пробуждение.id }) else { return .неизвестно }
        if !неизвестныеИсходы.isEmpty { return .неизвестно }
        return исходы.isEmpty ? .ожидать : .заявленоЗавершение
    }

    /// Решатель остаётся чистым: возвращаемая команда является предложением.
    public static func рассмотреть(наблюдение: НаблюдениеУзла, политика: ПолитикаРегуляцииУзла,
        idРешения: UUID, idКоманды: UUID, момент: Date,
        атрибуция: АтрибуцияРешенияУзла = .неизвестна) -> РешениеУзла {
        РешательАктивностиУзла.решить(наблюдение: наблюдение, политика: политика,
            idРешения: idРешения, idКоманды: idКоманды, момент: момент, атрибуция: атрибуция)
    }

    /// Сверяет только переданные DTO, не подтверждая происхождение или эффект.
    public static func сопоставить(команда: КомандаУзла, исход: ИсходКоманды) -> СогласованностьИсходаУзла {
        guard команда.id == исход.idКоманды,
              !команда.владелец.isEmpty,
              case .известно(let писатель) = команда.свидетельствоЕдинственногоПисателя,
              Data(писатель.utf8) == Data(команда.владелец.utf8),
              Data(команда.владелец.utf8) == Data(исход.владелец.utf8),
              исход.наблюдалосьВ >= команда.выданаВ,
              исход.наблюдалосьВ < команда.арендаДействуетДо,
              case .известно(let исходнаяВерсия) = команда.ожидаемаяВерсияСостояния,
              case .известно(let версияКоманды) = исход.ожидаемаяВерсияСостояния,
              case .известно(let новаяВерсия) = исход.наблюдаемаяВерсияСостояния,
              case .известно(let арендаИсхода) = исход.арендаДействуетДо,
              арендаИсхода == команда.арендаДействуетДо,
              исходнаяВерсия == версияКоманды, новаяВерсия > исходнаяВерсия,
              case .известно(let свидетельство) = исход.свидетельствоИлиКвитанция,
              !свидетельство.isEmpty else { return .неизвестно }
        switch исход.статус {
        case .completed, .failed: return .заявленныеДанныеСогласованы
        case .accepted, .queued, .running, .unknown: return .неизвестно
        }
    }

    /// Совмещает проекцию с заявленным исходом именно той команды пробуждения.
    /// Ни результат, ни входные DTO не удостоверяют происхождение или эффект.
    public static func сопоставитьПробуждение(ключ: КлючСвязиРодителя, события: [СобытиеСвязиРодителя],
        решение: РешениеУзла, исход: ИсходКоманды) -> СогласованностьИсходаУзла {
        guard проекция(ключ: ключ, события: события) == .заявленоЗавершение,
              let команда = решение.команда,
              let намерение = события.first(where: { $0.ключ == ключ && $0.вид == .намерениеПробуждения }),
              решение.статус == .разрешено, команда.действие == .resume, исход.статус == .completed,
              команда.id == намерение.id, команда.idПоручения == ключ.поручение,
              решение.ожидаемаяВерсияСостояния == команда.ожидаемаяВерсияСостояния,
              case .известно(let арендаРешения) = решение.арендаДействуетДо,
              арендаРешения == команда.арендаДействуетДо,
              case .известно(let контекст) = решение.контекстПоручения,
              контекст.id == команда.idПоручения,
              Data(контекст.владелец.utf8) == Data(команда.владелец.utf8),
              контекст.ожидаемаяВерсияСостояния == команда.ожидаемаяВерсияСостояния,
              команда.арендаДействуетДо <= контекст.грантДействуетДо,
              case .известно(let поручение) = решение.idПоручения, поручение == ключ.поручение else { return .неизвестно }
        // UUID адресата пока не связан с владельцем команды проверяемым источником.
        // Даже согласованные данные не подтверждают целевого адресата.
        return .неизвестно
    }
}

/// Чистая функция: возвращает план, но не запускает, не возобновляет и не останавливает процесс.
public enum РешательАктивностиУзла {
    public static func решить(
        наблюдение: НаблюдениеУзла,
        политика: ПолитикаРегуляцииУзла,
        idРешения: UUID,
        idКоманды: UUID,
        момент: Date,
        атрибуция: АтрибуцияРешенияУзла = .неизвестна
    ) -> РешениеУзла {
        let версияСостояния = наблюдение.состояние.версия
        let контекст = наблюдение.поручение
        func неизвестно(_ основание: КодОснованияРешения) -> РешениеУзла {
            .init(id: idРешения, idНаблюдения: наблюдение.id,
                idПоручения: идентификаторПоручения(контекст), исходнаяВерсия: .известно(наблюдение.версияИсточника),
                желаемаяАктивность: .неизвестно(причина: основание.rawValue), статус: .неизвестно,
                версияПолитики: политика.версия, версияСигналов: политика.версияСигналов,
                версияЧувствительности: политика.версияЧувствительности, основания: [основание],
                ожидаемаяВерсияСостояния: версияСостояния,
                арендаДействуетДо: .неизвестно(причина: основание.rawValue),
                контекстПоручения: контекст, атрибуция: атрибуция, команда: nil)
        }

        guard политика.корректна else { return неизвестно(.данныеНеизвестны) }
        guard момент >= наблюдение.наблюдалосьВ, момент < наблюдение.свежоДо,
              !наблюдение.источник.isEmpty, !наблюдение.версияИсточника.isEmpty else {
            return неизвестно(.наблюдениеУстарело)
        }
        guard наблюдение.версияИсточника == политика.версияСигналов else {
            return неизвестно(.версияСигналаНеСовпадает)
        }
        guard case .известно(let поручение) = контекст,
              корректноеПоручение(поручение), момент < поручение.грантДействуетДо,
              case .известно(let грант) = поручение.свидетельствоГранта,
              !грант.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return неизвестно(.поручениеНеПодтверждено)
        }
        guard case .известно(let писатель) = наблюдение.свидетельствоЕдинственногоПисателя,
              !писатель.isEmpty, писатель == поручение.владелец else {
            return неизвестно(.нетЕдинственногоПисателя)
        }
        guard case .известно(let ожидаемаяВерсия) = поручение.ожидаемаяВерсияСостояния,
              case .известно(let текущаяВерсия) = версияСостояния,
              ожидаемаяВерсия == текущаяВерсия,
              case .известно(let фаза) = наблюдение.состояние.фаза,
              case .известно(let текущийПараллелизм) = наблюдение.состояние.параллелизм,
              case .известно(let активныеРаботы) = наблюдение.состояние.активныеРаботы,
              текущийПараллелизм >= 0, активныеРаботы >= 0 else {
            return неизвестно(.данныеНеизвестны)
        }
        guard case .известно(let cpu) = наблюдение.бюджетРесурсов.свободныйCPUMilliCores,
              case .известно(let память) = наблюдение.бюджетРесурсов.свободнаяПамятьБайт,
              case .известно(let максимумУзла) = наблюдение.бюджетРесурсов.максимумПараллелизма,
              максимумУзла >= 0 else { return неизвестно(.данныеНеизвестны) }

        let свободноCPUСлотов = min(UInt64(Int.max), cpu / политика.CPUНаОдногоРаботникаMilliCores)
        let свободноСлотовПамяти = min(UInt64(Int.max), память / политика.памятьНаОдногоРаботникаБайт)
        let ресурсныйПредел = [
            политика.максимумПараллелизма, максимумУзла,
            Int(свободноCPUСлотов), Int(свободноСлотовПамяти)
        ].min() ?? 0
        let аренда = момент.addingTimeInterval(TimeInterval(политика.срокАрендыСекунд))
        guard аренда > момент, аренда.timeIntervalSinceReferenceDate.isFinite else {
            return неизвестно(.данныеНеизвестны)
        }

        if ресурсныйПредел < текущийПараллелизм {
            return сформировать(
                желаемыйПараллелизм: max(0, ресурсныйПредел), действие: активныеРаботы > 0 ? .checkpoint : .drain,
                основание: .ресурсноеДавление, наблюдение: наблюдение, поручение: поручение,
                политика: политика, idРешения: idРешения, idКоманды: idКоманды, момент: момент,
                аренда: аренда, текущаяВерсия: текущаяВерсия, фаза: фаза, атрибуция: атрибуция)
        }

        guard case .известно(let независимыеЗадачи) = наблюдение.сигналыРаботы.независимыеГотовыеЗадачи,
              case .известно(let полезныеРезультаты) = наблюдение.сигналыРаботы.полезныеПринятыеРезультаты,
              case .известно(let сбои) = наблюдение.сигналыРаботы.сбои,
              case .известно(let повторы) = наблюдение.сигналыРаботы.повторнаяРабота,
              case .известно(let p95) = наблюдение.сигналыРаботы.p95ЗадержкиМиллисекунды,
              case .известно(let затраты) = наблюдение.сигналыРаботы.затратыЕдиниц,
              case .известно(let простаиваетС) = наблюдение.сигналыРаботы.нетРаботыС,
              независимыеЗадачи >= 0, полезныеРезультаты >= 0, сбои >= 0, повторы >= 0 else {
            return неизвестно(.данныеНеизвестны)
        }

        let превышенПорогКачества = сбои > политика.максимумСбоевДляУвеличения
            || повторы > политика.максимумПовторнойРаботыДляУвеличения
            || p95 > политика.максимумP95Миллисекунд || затраты > политика.максимумЗатратЕдиниц
        let вОкнеГистерезиса: Bool
        if case .известно(let последнийПереход) = наблюдение.состояние.последнийПереход {
            вОкнеГистерезиса = момент.timeIntervalSince(последнийПереход) < TimeInterval(политика.окноГистерезисаСекунд)
        } else {
            вОкнеГистерезиса = true
        }

        if независимыеЗадачи == 0, активныеРаботы == 0,
           момент.timeIntervalSince(простаиваетС) >= TimeInterval(политика.льготныйПериодБезРаботыСекунд),
           текущийПараллелизм > 0 {
            return сформировать(
                желаемыйПараллелизм: 0, действие: .drain, основание: .нетНезависимойРаботы,
                наблюдение: наблюдение, поручение: поручение, политика: политика,
                idРешения: idРешения, idКоманды: idКоманды, момент: момент, аренда: аренда,
                текущаяВерсия: текущаяВерсия, фаза: фаза, атрибуция: атрибуция)
        }

        if превышенПорогКачества, текущийПараллелизм > 0, активныеРаботы == 0 {
            return сформировать(
                желаемыйПараллелизм: текущийПараллелизм - 1, действие: .drain,
                основание: .превышеныЛимитыРезультатов, наблюдение: наблюдение, поручение: поручение,
                политика: политика, idРешения: idРешения, idКоманды: idКоманды, момент: момент,
                аренда: аренда, текущаяВерсия: текущаяВерсия, фаза: фаза, атрибуция: атрибуция)
        }

        let качествоДопустимо = !превышенПорогКачества
            && полезныеРезультаты >= политика.минимумПолезныхРезультатовДляУвеличения
        let достаточноРаботы = независимыеЗадачи >= политика.минимумНезависимойРаботыДляУвеличения
        if качествоДопустимо, достаточноРаботы, текущийПараллелизм < ресурсныйПредел {
            guard !вОкнеГистерезиса else {
                return удержать(
                    целевойПараллелизм: текущийПараллелизм, основание: .гистерезис,
                    наблюдение: наблюдение, поручение: поручение, политика: политика,
                    idРешения: idРешения, момент: момент, аренда: аренда,
                    текущаяВерсия: текущаяВерсия, атрибуция: атрибуция)
            }
            let действие: ДействиеУзла = фаза == .приостанавливается ? .resume : .start
            return сформировать(
                желаемыйПараллелизм: текущийПараллелизм + 1, действие: действие,
                основание: .полезнаяНезависимаяРабота, наблюдение: наблюдение, поручение: поручение,
                политика: политика, idРешения: idРешения, idКоманды: idКоманды, момент: момент,
                аренда: аренда, текущаяВерсия: текущаяВерсия, фаза: фаза, атрибуция: атрибуция)
        }

        let основание: КодОснованияРешения
        if превышенПорогКачества { основание = .превышеныЛимитыРезультатов }
        else if независимыеЗадачи < политика.минимумНезависимойРаботыДляУвеличения { основание = .нетНезависимойРаботы }
        else if полезныеРезультаты < политика.минимумПолезныхРезультатовДляУвеличения { основание = .недостаточноПолезныхРезультатов }
        else { основание = .достигнутПределПараллелизма }
        return удержать(
            целевойПараллелизм: текущийПараллелизм, основание: основание,
            наблюдение: наблюдение, поручение: поручение, политика: политика,
            idРешения: idРешения, момент: момент, аренда: аренда,
            текущаяВерсия: текущаяВерсия, атрибуция: атрибуция)
    }

    private static func сформировать(
        желаемыйПараллелизм: Int, действие: ДействиеУзла, основание: КодОснованияРешения,
        наблюдение: НаблюдениеУзла, поручение: КонтекстПорученияУзла,
        политика: ПолитикаРегуляцииУзла, idРешения: UUID, idКоманды: UUID,
        момент: Date, аренда: Date, текущаяВерсия: UInt64, фаза: ФазаУзла,
        атрибуция: АтрибуцияРешенияУзла
    ) -> РешениеУзла {
        guard case .известно(let доступныеДействия) = наблюдение.возможности,
              доступныеДействия.contains(действие),
              case .известно(let писатель) = наблюдение.свидетельствоЕдинственногоПисателя,
              писатель == поручение.владелец else {
            return .init(id: idРешения, idНаблюдения: наблюдение.id, idПоручения: .известно(поручение.id),
                исходнаяВерсия: .известно(наблюдение.версияИсточника),
                желаемаяАктивность: .известно(активность(желаемыйПараллелизм, максимум: политика.максимумПараллелизма)),
                статус: .неизвестно, версияПолитики: политика.версия,
                версияСигналов: политика.версияСигналов, версияЧувствительности: политика.версияЧувствительности,
                основания: [основание, .действиеНедоступно], ожидаемаяВерсияСостояния: .известно(текущаяВерсия),
                арендаДействуетДо: .неизвестно(причина: "нет подтверждённой возможности или единственного писателя"),
                контекстПоручения: .известно(поручение), атрибуция: атрибуция, команда: nil)
        }
        let команда = КомандаУзла(
            id: idКоманды, действие: действие, владелец: поручение.владелец,
            свидетельствоЕдинственногоПисателя: .известно(писатель), idПоручения: поручение.id,
            ожидаемаяВерсияСостояния: .известно(текущаяВерсия), выданаВ: момент,
            арендаДействуетДо: аренда, целевойПараллелизм: желаемыйПараллелизм, атрибуция: атрибуция)
        return .init(id: idРешения, idНаблюдения: наблюдение.id, idПоручения: .известно(поручение.id),
            исходнаяВерсия: .известно(наблюдение.версияИсточника),
            желаемаяАктивность: .известно(активность(желаемыйПараллелизм, максимум: политика.максимумПараллелизма)),
            статус: .разрешено, версияПолитики: политика.версия,
            версияСигналов: политика.версияСигналов, версияЧувствительности: политика.версияЧувствительности,
            основания: [основание], ожидаемаяВерсияСостояния: .известно(текущаяВерсия),
            арендаДействуетДо: .известно(аренда), контекстПоручения: .известно(поручение),
            атрибуция: атрибуция, команда: команда)
    }

    private static func удержать(
        целевойПараллелизм: Int, основание: КодОснованияРешения,
        наблюдение: НаблюдениеУзла, поручение: КонтекстПорученияУзла,
        политика: ПолитикаРегуляцииУзла, idРешения: UUID, момент: Date, аренда: Date,
        текущаяВерсия: UInt64, атрибуция: АтрибуцияРешенияУзла
    ) -> РешениеУзла {
        .init(id: idРешения, idНаблюдения: наблюдение.id, idПоручения: .известно(поручение.id),
            исходнаяВерсия: .известно(наблюдение.версияИсточника),
            желаемаяАктивность: .известно(активность(целевойПараллелизм, максимум: политика.максимумПараллелизма)),
            статус: .удерживать, версияПолитики: политика.версия,
            версияСигналов: политика.версияСигналов, версияЧувствительности: политика.версияЧувствительности,
            основания: [основание], ожидаемаяВерсияСостояния: .известно(текущаяВерсия),
            арендаДействуетДо: .известно(аренда), контекстПоручения: .известно(поручение),
            атрибуция: атрибуция, команда: nil)
    }

    private static func активность(_ параллелизм: Int, максимум: Int) -> ЖелаемаяАктивностьУзла {
        let ступень: СтупеньАктивностиУзла
        if параллелизм == 0 { ступень = .остановлен }
        else if параллелизм == 1 { ступень = .ограниченный }
        else if параллелизм >= максимум { ступень = .расширенный }
        else { ступень = .обычный }
        return .init(ступень: ступень, параллелизм: параллелизм)
    }

    private static func корректноеПоручение(_ поручение: КонтекстПорученияУзла) -> Bool {
        !поручение.владелец.isEmpty && !поручение.владелецРодителя.isEmpty && !поручение.цель.isEmpty
            && поручение.исходнаяСсылка.hasPrefix("refs/heads/")
            && поручение.исходныйКоммит.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil
            && поручение.исходноеДерево.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil
            && поручение.sha256Манифеста.известноеЗначение(соответствует: #"\A[0-9a-f]{64}\z"#)
            && !поручение.путьМанифеста.isEmpty && !поручение.ожидаемыйRemote.isEmpty
            && !поручение.разрешённыеПути.isEmpty && !поручение.обязательныеПути.isEmpty
            && Set(поручение.разрешённыеПути).count == поручение.разрешённыеПути.count
            && Set(поручение.обязательныеПути).count == поручение.обязательныеПути.count
    }

    private static func идентификаторПоручения(_ знание: Знание<КонтекстПорученияУзла>) -> Знание<UUID> {
        switch знание {
        case .известно(let поручение): .известно(поручение.id)
        case .неизвестно(let причина): .неизвестно(причина: причина)
        }
    }
}

private extension Знание where Value == String {
    func известноеЗначение(соответствует шаблону: String) -> Bool {
        guard case .известно(let value) = self else { return false }
        return value.range(of: шаблону, options: .regularExpression) != nil
    }

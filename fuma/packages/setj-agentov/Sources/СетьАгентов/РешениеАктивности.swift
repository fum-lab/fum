public struct ПолитикаРегуляцииУзла: Codable, Equatable, Sendable {
    public let версия: String
    public let версияСигналов: String
    public let версияЧувствительности: String
    public let максимумПараллелизма: Int
    public let минимумНезависимойРаботыДляУвеличения: Int
    public let минимумПолезныхРезультатовДляУвеличения: Int
    public let максимумСбоевДляУвеличения: Int
    public let максимумПовторнойРаботыДляУвеличения: Int
    public let максимумP95Миллисекунд: UInt64
    public let максимумЗатратЕдиниц: UInt64
    public let CPUНаОдногоРаботникаMilliCores: UInt64
    public let памятьНаОдногоРаботникаБайт: UInt64
    public let срокАрендыСекунд: UInt64
    public let окноГистерезисаСекунд: UInt64
    public let льготныйПериодБезРаботыСекунд: UInt64

    public init(версия: String, версияСигналов: String, версияЧувствительности: String,
        максимумПараллелизма: Int, минимумНезависимойРаботыДляУвеличения: Int,
        минимумПолезныхРезультатовДляУвеличения: Int, максимумСбоевДляУвеличения: Int,
        максимумПовторнойРаботыДляУвеличения: Int, максимумP95Миллисекунд: UInt64,
        максимумЗатратЕдиниц: UInt64, CPUНаОдногоРаботникаMilliCores: UInt64,
        памятьНаОдногоРаботникаБайт: UInt64, срокАрендыСекунд: UInt64,
        окноГистерезисаСекунд: UInt64, льготныйПериодБезРаботыСекунд: UInt64) {
        self.версия = версия
        self.версияСигналов = версияСигналов
        self.версияЧувствительности = версияЧувствительности
        self.максимумПараллелизма = максимумПараллелизма
        self.минимумНезависимойРаботыДляУвеличения = минимумНезависимойРаботыДляУвеличения
        self.минимумПолезныхРезультатовДляУвеличения = минимумПолезныхРезультатовДляУвеличения
        self.максимумСбоевДляУвеличения = максимумСбоевДляУвеличения
        self.максимумПовторнойРаботыДляУвеличения = максимумПовторнойРаботыДляУвеличения
        self.максимумP95Миллисекунд = максимумP95Миллисекунд
        self.максимумЗатратЕдиниц = максимумЗатратЕдиниц
        self.CPUНаОдногоРаботникаMilliCores = CPUНаОдногоРаботникаMilliCores
        self.памятьНаОдногоРаботникаБайт = памятьНаОдногоРаботникаБайт
        self.срокАрендыСекунд = срокАрендыСекунд
        self.окноГистерезисаСекунд = окноГистерезисаСекунд
        self.льготныйПериодБезРаботыСекунд = льготныйПериодБезРаботыСекунд
    }

    fileprivate var корректна: Bool {
        !версия.isEmpty && !версияСигналов.isEmpty && !версияЧувствительности.isEmpty
            && максимумПараллелизма > 0
            && минимумНезависимойРаботыДляУвеличения > 0
            && минимумПолезныхРезультатовДляУвеличения >= 0
            && максимумСбоевДляУвеличения >= 0 && максимумПовторнойРаботыДляУвеличения >= 0
            && CPUНаОдногоРаботникаMilliCores > 0 && памятьНаОдногоРаботникаБайт > 0
            && срокАрендыСекунд > 0
    }
}

public struct КомандаУзла: Codable, Equatable, Sendable {
    public let id: UUID
    public let действие: ДействиеУзла
    public let владелец: String
    public let свидетельствоЕдинственногоПисателя: Знание<String>
    public let idПоручения: UUID
    public let ожидаемаяВерсияСостояния: Знание<UInt64>
    public let выданаВ: Date
    public let арендаДействуетДо: Date
    public let целевойПараллелизм: Int
    public let атрибуция: АтрибуцияРешенияУзла

    public init(id: UUID, действие: ДействиеУзла, владелец: String,
        свидетельствоЕдинственногоПисателя: Знание<String>, idПоручения: UUID,
        ожидаемаяВерсияСостояния: Знание<UInt64>, выданаВ: Date, арендаДействуетДо: Date,
        целевойПараллелизм: Int, атрибуция: АтрибуцияРешенияУзла) {
        self.id = id
        self.действие = действие
        self.владелец = владелец
        self.свидетельствоЕдинственногоПисателя = свидетельствоЕдинственногоПисателя
        self.idПоручения = idПоручения
        self.ожидаемаяВерсияСостояния = ожидаемаяВерсияСостояния
        self.выданаВ = выданаВ
        self.арендаДействуетДо = арендаДействуетДо
        self.целевойПараллелизм = целевойПараллелизм
        self.атрибуция = атрибуция
    }

    public func действительна(на момент: Date) -> Bool {
        guard !владелец.isEmpty, выданаВ <= момент, момент < арендаДействуетДо,
              целевойПараллелизм >= 0,
              case .известно = ожидаемаяВерсияСостояния,
              case .известно(let писатель) = свидетельствоЕдинственногоПисателя else { return false }
        return писатель == владелец
    }
}


public enum КодОснованияРешения: String, Codable, Sendable {
    case наблюдениеУстарело
    case версияСигналаНеСовпадает
    case данныеНеизвестны
    case поручениеНеПодтверждено
    case арендаИстекла
    case нетЕдинственногоПисателя
    case ресурсноеДавление
    case превышеныЛимитыРезультатов
    case нетНезависимойРаботы
    case недостаточноПолезныхРезультатов
    case гистерезис
    case достигнутПределПараллелизма
    case полезнаяНезависимаяРабота
    case режимУдержан
    case действиеНедоступно
}


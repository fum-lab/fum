@Test func понижениеТребуетПодтвержденияУстойчивостиИАвтоматизации() {
    let без = контекст(запрошено: .известно(конфигурация(.medium)), наблюдается: .известно(конфигурация(.high)))
    #expect(ПереходУсилия.предложить(без, история: []).состояние == .неизвестно)
    let с = контекст(запрошено: .известно(конфигурация(.medium)), наблюдается: .известно(конфигурация(.high)),
        устойчивость: .известно("synthetic stable"), автоматизация: .известно("synthetic automation"),
        происхождение: .известно("synthetic source"))
    #expect(ПереходУсилия.предложить(с, история: []).состояние == .предложено(конфигурация(.medium)))
    let безАвтоматизации = контекст(запрошено: .известно(конфигурация(.medium)), наблюдается: .известно(конфигурация(.high)),
        устойчивость: .известно("synthetic stable"), происхождение: .известно("synthetic source"))
    #expect(ПереходУсилия.предложить(безАвтоматизации, история: []).состояние == .неизвестно)
    let безПроисхождения = контекст(запрошено: .известно(конфигурация(.medium)), наблюдается: .известно(конфигурация(.high)),
        устойчивость: .известно("synthetic stable"), автоматизация: .известно("synthetic automation"))
    #expect(ПереходУсилия.предложить(безПроисхождения, история: []).состояние == .неизвестно)
}


@Test func каждаяМодельПроходитСоседниеСтупениВверхИВниз() {
    for модель in ["gpt-6.1-sol", "gpt-6.1-terra", "gpt-6-sol", "gpt-6-luna",
                   "gpt-6-astra", "gpt-5.6-sol", "gpt-5.6-terra", "gpt-5.6-luna"] {
        let ступени = ступениДляСинтетическойМодели(модель)
        for индекс in 0..<(ступени.count - 1) {
            let ниже = конфигурация(ступени[индекс], модель: модель)
            let выше = конфигурация(ступени[индекс + 1], модель: модель)
            let вверх = контекст(запрошено: .известно(выше), наблюдается: .известно(ниже),
                затруднение: .известно("synthetic difficulty"))
            let предложениеВверх = ПереходУсилия.предложить(вверх, история: [])
            #expect(предложениеВверх.состояние == .предложено(выше))
            #expect(предложениеВверх.история.last?.предыдущая == ниже)
            #expect(предложениеВверх.история.last?.предложенная == выше)
            #expect(предложениеВверх.история.last?.наблюдаемоеПосле == .неизвестно(причина: "после предложения отдельное наблюдение не передавалось"))
            #expect(предложениеВверх.история.last?.причина == "synthetic reason")
            #expect(предложениеВверх.история.last?.основание == "synthetic difficulty")
            #expect(предложениеВверх.история.last?.инициатор == "synthetic caller")
            #expect(предложениеВверх.история.last?.наблюдение == "synthetic difficulty")

            let вниз = контекст(запрошено: .известно(ниже), наблюдается: .известно(выше),
                устойчивость: .известно("synthetic stability"), автоматизация: .известно("synthetic automation"),
                происхождение: .известно("synthetic provenance"))
            let предложениеВниз = ПереходУсилия.предложить(вниз, история: [])
            #expect(предложениеВниз.состояние == .предложено(ниже))
            #expect(предложениеВниз.история.last?.предыдущая == выше)
            #expect(предложениеВниз.история.last?.предложенная == ниже)
            #expect(предложениеВниз.история.last?.наблюдаемоеПосле == .неизвестно(причина: "после предложения отдельное наблюдение не передавалось"))
            #expect(предложениеВниз.история.last?.основание.contains("synthetic stability") == true)
        }
    }
}


import Foundation
import Testing
@testable import СетьАгентов

private let модель = "gpt-6-luna"

private func конфигурация(_ усилие: СтупеньУсилия) -> КонфигурацияМоделиУсилия {
    .init(модель: модель, усилие: усилие)
}

private func контекст(
    запрошено: Знание<КонфигурацияМоделиУсилия>,
    наблюдается: Знание<КонфигурацияМоделиУсилия>,
    поддерживаются: Знание<[СтупеньУсилия]> = .известно(СтупеньУсилия.allCases),
    затруднение: Знание<String> = .неизвестно(причина: "нет наблюдения"),
    устойчивость: Знание<String> = .неизвестно(причина: "нет наблюдения"),
    автоматизация: Знание<String> = .неизвестно(причина: "нет наблюдения"),
    происхождение: Знание<String> = .неизвестно(причина: "нет происхождения"),
    инициатор: Знание<String> = .известно("synthetic caller"),
    причина: Знание<String> = .известно("synthetic reason")
) -> ВходПереходаУсилия {
    .init(запрошенная: запрошено, наблюдаемая: наблюдается, поддерживаемыеСтупени: поддерживаются,
          наблюдениеЗатруднения: затруднение,
          свидетельствоПонижения: .init(устойчивость: устойчивость, автоматизация: автоматизация, происхождение: происхождение),
          инициатор: инициатор, причина: причина)
}

@Test func повышениеИдётРовноНаОднуПоддерживаемуюСтупень() {
    let вход = контекст(запрошено: .известно(конфигурация(.medium)), наблюдается: .известно(конфигурация(.low)),
        затруднение: .известно("synthetic difficulty"))
    let результат = ПереходУсилия.предложить(вход, история: [])
    #expect(результат.состояние == .предложено(конфигурация(.medium)))
    #expect(результат.история.count == 1)
}


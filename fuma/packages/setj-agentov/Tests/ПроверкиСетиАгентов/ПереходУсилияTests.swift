private let модельLuna = "gpt-6-luna"

private func конфигурация(_ усилие: СтупеньУсилия, модель: String = модельLuna) -> КонфигурацияМоделиУсилия {
    .init(модель: модель, усилие: усилие)
}

private let всеСтупени = СтупеньУсилия.allCases
private let ступениLuna = всеСтупени.filter { $0 != .ultra }
private let каталогМоделей = [
    ("gpt-6.1-sol", всеСтупени), ("gpt-6-astra", всеСтупени),
    ("gpt-6.1-terra", всеСтупени), ("gpt-6-sol", всеСтупени), ("gpt-6-luna", ступениLuna),
    ("gpt-5.6-sol", всеСтупени), ("gpt-5.6-terra", всеСтупени), ("gpt-5.6-luna", ступениLuna)
].map { запись in
    let (модель, ступени) = запись
    ВозможностиУсилияМодели(модель: модель, ступени: ступени,
        источник: .известно("synthetic copy of mcp__codex_app__create_thread model schema"),
        версияСхемыКаталога: .неизвестно(причина: "synthetic schema version not provided"),
        версияВнешнегоПровайдера: .неизвестно(причина: "not observed or attested"))
}

private func ступениДляСинтетическойМодели(_ модель: String) -> [СтупеньУсилия] {
    каталогМоделей.first(where: { $0.модель == модель })?.ступени ?? []
}

private func каталогДляLuna(_ ступени: [СтупеньУсилия]) -> Знание<[ВозможностиУсилияМодели]> {
    .известно([ВозможностиУсилияМодели(модель: модельLuna, ступени: ступени,
        источник: .известно("synthetic catalog"),
        версияСхемыКаталога: .неизвестно(причина: "not separately versioned"),
        версияВнешнегоПровайдера: .неизвестно(причина: "not observed"))])
}

private func контекст(
    запрошено: Знание<КонфигурацияМоделиУсилия>,
    наблюдается: Знание<КонфигурацияМоделиУсилия>,
    каталог: Знание<[ВозможностиУсилияМодели]> = .известно(каталогМоделей),
    затруднение: Знание<String> = .неизвестно(причина: "нет наблюдения"),
    устойчивость: Знание<String> = .неизвестно(причина: "нет наблюдения"),
    автоматизация: Знание<String> = .неизвестно(причина: "нет наблюдения"),
    происхождение: Знание<String> = .неизвестно(причина: "нет происхождения"),
    инициатор: Знание<String> = .известно("synthetic caller"),
    причина: Знание<String> = .известно("synthetic reason")
) -> ВходПереходаУсилия {
    return .init(запрошенная: запрошено, наблюдаемая: наблюдается,
          каталогМоделей: каталог,
          наблюдениеЗатруднения: затруднение,
          свидетельствоПонижения: .init(устойчивость: устойчивость, автоматизация: автоматизация, происхождение: происхождение),
          инициатор: инициатор, причина: причина)
}


import Foundation
import Testing
@testable import СетьАгентов

private func исходДляПолезности(id: UUID = UUID(uuidString: "00000000-0000-4000-8000-000000000001")!, время: Date = Date(timeIntervalSince1970: 10),
    статус: СтатусИсходаКоманды = .completed, полезные: Знание<Int> = .известно(5),
    затраты: Знание<UInt64> = .известно(2), квитанция: Знание<String> = .известно("fixture")) -> ИсходКоманды {
    .init(idКоманды: id, владелец: "fixture", наблюдалосьВ: время,
        ожидаемаяВерсияСостояния: .известно(1), наблюдаемаяВерсияСостояния: .известно(2),
        арендаДействуетДо: .известно(Date(timeIntervalSince1970: 20)), статус: статус,
        наблюдаемыйPID: .неизвестно(причина: "fixture"), кодЗавершения: .неизвестно(причина: "fixture"),
        свидетельствоИлиКвитанция: квитанция, полезныеРезультаты: полезные,
        задержкаМиллисекунды: .неизвестно(причина: "fixture"), затратыЕдиниц: затраты,
        лимиты: .неизвестно(причина: "fixture"), сбои: .неизвестно(причина: "fixture"), причина: .неизвестно(причина: "fixture"))
}

@Test func сводкаДаётТолькоЗаявленнуюДробь() {
    let итог = ПолезностьКоманд.свести(исходы: [исходДляПолезности()],
        начало: Date(timeIntervalSince1970: 0), конец: Date(timeIntervalSince1970: 20))
    guard case .заявлено(let сводка) = итог else { Issue.record("ожидалась заявленная сводка"); return }
    #expect(сводка.команд == 1)
    #expect(сводка.заявленныхРезультатов == 5)
    #expect(сводка.заявленныхЗатрат == 2)
    #expect(сводка.отношение?.числитель == 5)
    #expect(сводка.отношение?.знаменатель == 2)
}

@Test func повторИлиНезавершённостьНеВыдаютПолнуюСумму() {
    let запись = исходДляПолезности()
    let начало = Date(timeIntervalSince1970: 0), конец = Date(timeIntervalSince1970: 20)
    #expect(ПолезностьКоманд.свести(исходы: [запись, запись], начало: начало, конец: конец) == .неизвестно(.повторID))
    let второйID = UUID(uuidString: "00000000-0000-4000-8000-000000000002")!
    #expect(ПолезностьКоманд.свести(исходы: [запись, исходДляПолезности(id: второйID, статус: .running)], начало: начало, конец: конец) == .неизвестно(.нетТерминала))
    #expect(ПолезностьКоманд.свести(исходы: [исходДляПолезности(полезные: .известно(-1))], начало: начало, конец: конец) == .неизвестно(.отрицательнаяПолезность))
    #expect(ПолезностьКоманд.свести(исходы: [исходДляПолезности(квитанция: .неизвестно(причина: "fixture"))], начало: начало, конец: конец) == .неизвестно(.нетЗаявленнойКвитанции))
    #expect(ПолезностьКоманд.свести(исходы: [исходДляПолезности(квитанция: .известно(" \n"))], начало: начало, конец: конец) == .неизвестно(.нетЗаявленнойКвитанции))
    #expect(ПолезностьКоманд.свести(исходы: [исходДляПолезности(время: конец)], начало: начало, конец: конец) == .неизвестно(.внеОкна))
}

@Test func переполнениеИНулевыеЗатратыНеВыдаютНеверноеОтношение() {
    let начало = Date(timeIntervalSince1970: 0), конец = Date(timeIntervalSince1970: 20)
    let второйID = UUID(uuidString: "00000000-0000-4000-8000-000000000002")!
    let третийID = UUID(uuidString: "00000000-0000-4000-8000-000000000003")!
    let переполнение = [исходДляПолезности(затраты: .известно(UInt64.max)), исходДляПолезности(id: второйID, затраты: .известно(1))]
    #expect(ПолезностьКоманд.свести(исходы: переполнение, начало: начало, конец: конец) == .неизвестно(.переполнение))
    let ноль = ПолезностьКоманд.свести(исходы: [исходДляПолезности(затраты: .известно(0))], начало: начало, конец: конец)
    guard case .заявлено(let сводка) = ноль else { Issue.record("ожидалась заявленная сводка"); return }
    #expect(сводка.отношение?.знаменатель == nil)
    if Int.bitWidth == 64 {
        let много = [исходДляПолезности(полезные: .известно(Int.max)),
                     исходДляПолезности(id: второйID, полезные: .известно(Int.max)),
                     исходДляПолезности(id: третийID, полезные: .известно(2))]
        #expect(ПолезностьКоманд.свести(исходы: много, начало: начало, конец: конец) == .неизвестно(.переполнение))
    }
}

@Test func неизвестныеПоляИПустоеОкноНеДаютСводку() {
    let начало = Date(timeIntervalSince1970: 0), конец = Date(timeIntervalSince1970: 20)
    #expect(ПолезностьКоманд.свести(исходы: [], начало: начало, конец: конец) == .неизвестно(.нетДанных))
    #expect(ПолезностьКоманд.свести(исходы: [исходДляПолезности()], начало: начало, конец: начало) == .неизвестно(.неверноеОкно))
    #expect(ПолезностьКоманд.свести(исходы: [исходДляПолезности(полезные: .неизвестно(причина: "fixture"))], начало: начало, конец: конец) == .неизвестно(.нетПолезности))
    #expect(ПолезностьКоманд.свести(исходы: [исходДляПолезности(затраты: .неизвестно(причина: "fixture"))], начало: начало, конец: конец) == .неизвестно(.нетЗатрат))
    #expect(ПолезностьКоманд.свести(исходы: Array(repeating: исходДляПолезности(), count: 2049), начало: начало, конец: конец) == .неизвестно(.превышенПредел))
}

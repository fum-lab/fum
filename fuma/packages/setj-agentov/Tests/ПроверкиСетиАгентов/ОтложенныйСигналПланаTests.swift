import Foundation
import Testing
@testable import СетьАгентов

@Suite struct ПроверкиОтложенногоСигналаПлана {
    private let шаг = "сверить-следующее-разрешённое-обязательство"

    private func состояние() -> СостояниеСигналовПлана {
        let план = ПланРаботыСигнала(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000001")!,
            следующийРазрешённыйШаг: .известно(шаг),
            попытка: ПопыткаРаботыСигнала(
                id: UUID(uuidString: "00000000-0000-4000-8000-000000000002")!,
                исход: .известно(.выполняется)))
        return СостояниеСигналовПлана(план: план)
    }

    private func сигнал(_ id: String, _ payload: [UInt8]) -> СигналРаботыПлана {
        СигналРаботыПлана(id: UUID(uuidString: id)!, данные: Data(payload))
    }

    @Test func входящийСигналСохраняетОсновнойПланПопыткуИПорядок() {
        let исходное = состояние()
        let первый = сигнал("00000000-0000-4000-8000-000000000003", [1, 2])
        let второй = сигнал("00000000-0000-4000-8000-000000000004", [3, 4])

        let послеПервого = ОтложенныйСигналПлана.сократить(исходное, событие: .сигнал(первый))
        guard case .отложено(let сПервым) = послеПервого else {
            Issue.record("активная попытка должна отложить сигнал")
            return
        }
        let послеВторого = ОтложенныйСигналПлана.сократить(сПервым, событие: .сигнал(второй))
        guard case .отложено(let итог) = послеВторого else {
            Issue.record("второй сигнал должен остаться в очереди")
            return
        }

        #expect(итог.план == исходное.план)
        #expect(итог.сигналы.map(\.сигнал) == [первый, второй])
        #expect(итог.сигналы.allSatisfy { $0.состояние == .ожидаетИсхода })
    }


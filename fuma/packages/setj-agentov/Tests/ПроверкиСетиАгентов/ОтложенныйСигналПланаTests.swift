    @Test func неизвестнаяОбработкаСохраняетСигналИНикогдаНеПереПредлагаетЕго() {
        let исходное = состояние()
        let первый = сигнал("00000000-0000-4000-8000-000000000015", [5])
        let второй = сигнал("00000000-0000-4000-8000-000000000016", [6])
        guard case .отложено(let сПервым) = ОтложенныйСигналПлана.сократить(исходное, событие: .сигнал(первый)),
              case .отложено(let оба) = ОтложенныйСигналПлана.сократить(сПервым, событие: .сигнал(второй)) else {
            Issue.record("оба сигнала должны сохраниться")
            return
        }
        let исход = ИсходПопыткиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000017")!,
            попытка: исходное.план.попытка.id, статус: .завершена,
            доступностьСледующегоШага: .известно(.разрешён))
        guard case .продолжить(_, _, let послеИсхода) = ОтложенныйСигналПлана.сократить(оба, событие: .исход(исход)) else {
            Issue.record("известный исход должен открыть голову очереди")
            return
        }
        let неизвестноеПодтверждение = ПодтверждениеОбработкиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000018")!,
            сигнал: первый.id, статус: .неизвестно)
        guard case .неизвестно(_, let послеНеизвестногоИсхода) =
            ОтложенныйСигналПлана.сократить(послеИсхода, событие: .подтверждение(неизвестноеПодтверждение)) else {
            Issue.record("неизвестная обработка должна остаться UNKNOWN")
            return
        }
        #expect(послеНеизвестногоИсхода.сигналы.first?.состояние == .неизвестныйИсход)
        guard case .безИзменений(let повторНеизвестногоПодтверждения) =
            ОтложенныйСигналПлана.сократить(послеНеизвестногоИсхода, событие: .подтверждение(неизвестноеПодтверждение)) else {
            Issue.record("повтор неизвестного подтверждения не должен запускать повторную обработку")
            return
        }
        #expect(повторНеизвестногоПодтверждения == послеНеизвестногоИсхода)
        guard case .отложено(let послеНового) = ОтложенныйСигналПлана.сократить(послеНеизвестногоИсхода, событие: .сигнал(сигнал("00000000-0000-4000-8000-000000000019", [7]))) else {
            Issue.record("UNKNOWN головы должен удерживать FIFO")
            return
        }
        #expect(послеНового.сигналы.map(\.сигнал) == [первый, второй,
            сигнал("00000000-0000-4000-8000-000000000019", [7])])
        #expect(послеНового.сигналы.first?.состояние == .неизвестныйИсход)
        #expect(послеНового.сигналы.dropFirst().allSatisfy { $0.состояние == .ожидаетИсхода })
    }

    @Test func наблюдениеСвязанногоИсходаВосстанавливаетUNKNOWNИПродвигаетFIFO() {
        let исходное = состояние()
        let первый = сигнал("00000000-0000-4000-8000-000000000020", [1, 8])
        let второй = сигнал("00000000-0000-4000-8000-000000000021", [2, 8])
        guard case .отложено(let сПервым) = ОтложенныйСигналПлана.сократить(исходное, событие: .сигнал(первый)),
              case .отложено(let оба) = ОтложенныйСигналПлана.сократить(сПервым, событие: .сигнал(второй)) else {
            Issue.record("сигналы должны сохраниться в FIFO")
            return
        }
        let исход = ИсходПопыткиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000022")!,
            попытка: исходное.план.попытка.id, статус: .завершена,
            доступностьСледующегоШага: .известно(.разрешён))
        guard case .продолжить(_, _, let предложено) = ОтложенныйСигналПлана.сократить(оба, событие: .исход(исход)) else {
            Issue.record("терминальный исход должен однократно предложить голову FIFO")
            return
        }
        let неизвестноеПодтверждение = ПодтверждениеОбработкиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000023")!,
            сигнал: первый.id, статус: .неизвестно)
        guard case .неизвестно(_, let сUNKNOWN) = ОтложенныйСигналПлана.сократить(
            предложено, событие: .подтверждение(неизвестноеПодтверждение)) else {
            Issue.record("неизвестный исход обработки должен удержать первую голову")
            return
        }
        let неверноеНаблюдение = НаблюдениеОбработкиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000024")!,
            сигнал: первый.id, попытка: UUID(uuidString: "00000000-0000-4000-8000-000000000025")!,
            происхождение: .известно("fixture.source"), результат: .известно(.обработан))
        guard case .неизвестно(_, let послеНесовпадения) = ОтложенныйСигналПлана.сократить(
            сUNKNOWN, событие: .наблюдениеОбработки(неверноеНаблюдение)) else {
            Issue.record("несовпавшая попытка не должна разрешить UNKNOWN")
            return
        }
        #expect(послеНесовпадения == сUNKNOWN)
        let безПроисхождения = НаблюдениеОбработкиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000026")!,
            сигнал: первый.id, попытка: исходное.план.попытка.id,
            происхождение: .неизвестно(причина: "fixture"), результат: .известно(.обработан))
        guard case .неизвестно(_, let послеПробела) = ОтложенныйСигналПлана.сократить(
            сUNKNOWN, событие: .наблюдениеОбработки(безПроисхождения)) else {
            Issue.record("UNKNOWN provenance не должен разрешить сигнал")
            return
        }
        #expect(послеПробела == сUNKNOWN)

        let наблюдение = НаблюдениеОбработкиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000027")!,
            сигнал: первый.id, попытка: исходное.план.попытка.id,
            происхождение: .известно("fixture.source:observation-27"), результат: .известно(.обработан))
        guard case .продолжить(let следующийШаг, let следующийСигнал, let послеНаблюдения) =
            ОтложенныйСигналПлана.сократить(сUNKNOWN, событие: .наблюдениеОбработки(наблюдение)) else {
            Issue.record("позднее согласованное наблюдение должно снять только UNKNOWN голову и продвинуть FIFO")
            return
        }
        #expect(следующийШаг == шаг)
        #expect(следующийСигнал == второй)
        #expect(послеНаблюдения.сигналы.count == 1)
        #expect(послеНаблюдения.сигналы.first?.состояние == .предложенКРассмотрению)
        #expect(послеНаблюдения.наблюденияОбработки == [наблюдение])
        guard case .безИзменений(let повтор) = ОтложенныйСигналПлана.сократить(
            послеНаблюдения, событие: .наблюдениеОбработки(наблюдение)) else {
            Issue.record("повтор наблюдения не должен повторить обработку")
            return
        }
        #expect(повтор == послеНаблюдения)
    }


    @Test func известныйТерминальныйИсходОдинРазПредлагаетПрежнийШаг() {
        let исходное = состояние()
        let первыйСигнал = сигнал("00000000-0000-4000-8000-000000000007", [9, 0])
        let второйСигнал = сигнал("00000000-0000-4000-8000-000000000012", [4, 2])
        guard case .отложено(let сПервым) = ОтложенныйСигналПлана.сократить(исходное, событие: .сигнал(первыйСигнал)),
              case .отложено(let отложенное) = ОтложенныйСигналПлана.сократить(сПервым, событие: .сигнал(второйСигнал)) else {
            Issue.record("ожидался отложенный сигнал")
            return
        }
        let исход = ИсходПопыткиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000008")!,
            попытка: исходное.план.попытка.id, статус: .завершена,
            доступностьСледующегоШага: .известно(.разрешён))
        let переход = ОтложенныйСигналПлана.сократить(отложенное, событие: .исход(исход))
        guard case .продолжить(let следующийШаг, let предложенныйСигнал, let итог) = переход else {
            Issue.record("терминальный исход должен предложить сохранённое продолжение")
            return
        }

        #expect(следующийШаг == шаг)
        #expect(предложенныйСигнал == первыйСигнал)
        #expect(итог.план.следующийРазрешённыйШаг == исходное.план.следующийРазрешённыйШаг)
        #expect(итог.план.попытка.id == исходное.план.попытка.id)
        #expect(итог.план.попытка.исход == .известно(.завершена))
        #expect(итог.сигналы.first?.состояние == .предложенКРассмотрению)

        let неверноеПодтверждение = ПодтверждениеОбработкиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000013")!,
            сигнал: второйСигнал.id, статус: .обработан)
        guard case .неизвестно(_, let сохранённое) =
            ОтложенныйСигналПлана.сократить(итог, событие: .подтверждение(неверноеПодтверждение)) else {
            Issue.record("подтверждение сигнала вне головы FIFO должно дать UNKNOWN")
            return
        }
        #expect(сохранённое == итог)

        let подтверждение = ПодтверждениеОбработкиСигналаПлана(
            id: UUID(uuidString: "00000000-0000-4000-8000-000000000014")!,
            сигнал: первыйСигнал.id, статус: .обработан)
        guard case .продолжить(let следующийПослеПодтверждения, let следующийСигнал, let послеПодтверждения) =
            ОтложенныйСигналПлана.сократить(итог, событие: .подтверждение(подтверждение)) else {
            Issue.record("подтверждение головы FIFO должно открыть следующий сигнал по порядку")
            return
        }
        #expect(следующийПослеПодтверждения == шаг)
        #expect(следующийСигнал == второйСигнал)

        guard case .безИзменений(let повторПодтверждения) =
            ОтложенныйСигналПлана.сократить(послеПодтверждения, событие: .подтверждение(подтверждение)) else {
            Issue.record("повтор подтверждения не должен повторить предложение")
            return
        }
        #expect(повторПодтверждения == послеПодтверждения)
        guard case .безИзменений(let повторИсхода) = ОтложенныйСигналПлана.сократить(послеПодтверждения, событие: .исход(исход)) else {
            Issue.record("повтор терминального исхода не должен повторить предложение")
            return
        }
        #expect(повторИсхода == послеПодтверждения)
    }


import Foundation
import Testing
@testable import СетьАгентов

@Suite struct ПроверкиИсходаКоманды {
    private let время = Date(timeIntervalSince1970: 1_800_000_000)
    private let неизвестнаяПричина = "источник исхода не сообщил значение"

    private func создатьИсход(
        _ статус: СтатусИсходаКоманды,
        ожидаемаяВерсия: Знание<UInt64> = .известно(7),
        наблюдаемаяВерсия: Знание<UInt64> = .неизвестно(причина: "источник исхода не сообщил значение")
    ) -> ИсходКоманды {
        .init(
            idКоманды: UUID(), владелец: "узел-тест", наблюдалосьВ: время,
            ожидаемаяВерсияСостояния: ожидаемаяВерсия,
            наблюдаемаяВерсияСостояния: наблюдаемаяВерсия,
            арендаДействуетДо: .неизвестно(причина: неизвестнаяПричина),
            статус: статус,
            наблюдаемыйPID: .неизвестно(причина: неизвестнаяПричина),
            кодЗавершения: .неизвестно(причина: неизвестнаяПричина),
            свидетельствоИлиКвитанция: .неизвестно(причина: неизвестнаяПричина),
            полезныеРезультаты: .неизвестно(причина: неизвестнаяПричина),
            задержкаМиллисекунды: .неизвестно(причина: неизвестнаяПричина),
            затратыЕдиниц: .неизвестно(причина: неизвестнаяПричина),
            лимиты: .неизвестно(причина: неизвестнаяПричина),
            сбои: .неизвестно(причина: неизвестнаяПричина),
            причина: .неизвестно(причина: неизвестнаяПричина)
        )
    }

    @Test func неизвестныйИсходНеСчитаетсяЗавершённымИНеРазрешаетПовторПоНовойВерсии() {
        let исход = создатьИсход(.unknown)
        let исходБезОжидаемойВерсии = создатьИсход(
            .unknown, ожидаемаяВерсия: .неизвестно(причина: неизвестнаяПричина))
        let исходССогласованнойВерсией = создатьИсход(.unknown, наблюдаемаяВерсия: .известно(8))

        #expect(!исход.эффектЗавершён)
        #expect(!исход.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
        #expect(!исход.допускаетНовуюКоманду(сВерсиейНаблюдения: 70))
        #expect(!исходБезОжидаемойВерсии.допускаетНовуюКоманду(сВерсиейНаблюдения: 70))
        #expect(!исходССогласованнойВерсией.эффектЗавершён)
        #expect(!исходССогласованнойВерсией.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
    }

    @Test func активныйИсходНеРазрешаетНовуюКоманду() {
        for статус in [СтатусИсходаКоманды.accepted, .queued, .running] {
            let исход = создатьИсход(статус)
            let исходССогласованнойВерсией = создатьИсход(статус, наблюдаемаяВерсия: .известно(8))

            #expect(!исход.эффектЗавершён)
            #expect(!исход.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
            #expect(!исходССогласованнойВерсией.эффектЗавершён)
            #expect(!исходССогласованнойВерсией.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
        }
    }

    @Test func явныйТерминальныйИсходТребуетБолееНовуюВерсиюДляСледующейКоманды() {
        for статус in [СтатусИсходаКоманды.completed, .failed] {
            let исход = создатьИсход(статус, наблюдаемаяВерсия: .известно(8))

            #expect(исход.эффектЗавершён)
            #expect(!исход.допускаетНовуюКоманду(сВерсиейНаблюдения: 7))
            #expect(исход.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
        }
    }

    @Test func терминальныйИсходОтклоняетНеизвестнуюИНесогласованнуюНаблюдаемуюВерсию() {
        for статус in [СтатусИсходаКоманды.completed, .failed] {
            let безНаблюдения = создатьИсход(
                статус, наблюдаемаяВерсия: .неизвестно(причина: неизвестнаяПричина))
            let большеПереданной = создатьИсход(статус, наблюдаемаяВерсия: .известно(9))
            let меньшеПереданной = создатьИсход(статус, наблюдаемаяВерсия: .известно(8))
            let равнаОжидаемой = создатьИсход(статус, наблюдаемаяВерсия: .известно(7))
            let меньшеОжидаемой = создатьИсход(статус, наблюдаемаяВерсия: .известно(6))
            let безОжидаемой = создатьИсход(
                статус, ожидаемаяВерсия: .неизвестно(причина: неизвестнаяПричина),
                наблюдаемаяВерсия: .известно(8))

            #expect(!безНаблюдения.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
            #expect(!большеПереданной.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
            #expect(!меньшеПереданной.допускаетНовуюКоманду(сВерсиейНаблюдения: 9))
            #expect(!равнаОжидаемой.допускаетНовуюКоманду(сВерсиейНаблюдения: 7))
            #expect(!меньшеОжидаемой.допускаетНовуюКоманду(сВерсиейНаблюдения: 6))
            #expect(!безОжидаемой.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
        }
    }

    @Test func согласованностьВерсийНеЯвляетсяОдноразовымОграждением() {
        let исход = создатьИсход(.completed, наблюдаемаяВерсия: .известно(8))
        #expect(исход.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
        #expect(исход.допускаетНовуюКоманду(сВерсиейНаблюдения: 8))
    }
}

import XCTest
import РечевыеПути

final class ПроверкиПоиска: XCTestCase {
  typealias Поиск = ПоискРечевыхПутей

  func вход(узлы: [Поиск.Узел], рёбра: [Поиск.Ребро], словарь: [Поиск.Слово], полный: Bool = true) -> Поиск.Вход {
    Поиск.Вход(полный: полный, начало: "s", конец: "f", узлы: узлы, рёбра: рёбра, словарь: словарь)
  }

  func test_СловарноеСостояниеНеТеряетсяНаСходящейсяВершине() throws {
    let данные = вход(
      узлы: [.init("s", 0), .init("m", 1), .init("f", 2)],
      рёбра: [.init("сильное", из: "s", в: "m", символ: "x", вес: 10),
               .init("слабое", из: "s", в: "m", символ: "y", вес: -10),
               .init("конец", из: "m", в: "f", символ: "q", вес: 0)],
      словарь: [.init("xz", фонемы: ["x", "z"], текст: "xz", язык: "ru"),
                .init("yq", фонемы: ["y", "q"], текст: "yq", язык: "en")])
    guard case .кандидат(let кандидат) = try Поиск.выполнить(данные) else { return XCTFail("Нет допустимого пути") }
    XCTAssertEqual(кандидат.рёбра, ["слабое", "конец"])
    XCTAssertEqual(кандидат.оценка, -10)
    XCTAssertEqual(кандидат.сегменты.map(\.слово), ["yq"])
  }

  func test_ДваЯзыкаСохраняютГраницыСлов() throws {
    let данные = вход(
      узлы: [.init("s", 0), .init("m", 160), .init("f", 320)],
      рёбра: [.init("r", из: "s", в: "m", символ: "k", вес: -2),
               .init("e", из: "m", в: "f", символ: "d", вес: -3)],
      словарь: [.init("ru", фонемы: ["k"], текст: "кот", язык: "ru"),
                .init("en", фонемы: ["d"], текст: "dog", язык: "en")])
    guard case .кандидат(let кандидат) = try Поиск.выполнить(данные) else { return XCTFail("Нет смешанного пути") }
    XCTAssertEqual(кандидат.оценка, -5)
    XCTAssertEqual(кандидат.сегменты.map(\.слово), ["кот", "dog"])
    XCTAssertEqual(кандидат.сегменты.map(\.язык), ["ru", "en"])
    XCTAssertEqual(кандидат.сегменты.map(\.начало), [0, 160])
    XCTAssertEqual(кандидат.сегменты.map(\.конец), [160, 320])
  }

  func test_РавныеОценкиНеЗависятОтПорядкаВхода() throws {
    let узлы: [Поиск.Узел] = [.init("s", 0), .init("f", 1)]
    let рёбра: [Поиск.Ребро] = [.init("b", из: "s", в: "f", символ: "x", вес: 1),
                                 .init("a", из: "s", в: "f", символ: "x", вес: 1)]
    let словарь: [Поиск.Слово] = [.init("z", фонемы: ["x"], текст: "z", язык: "ru"),
                                  .init("a", фонемы: ["x"], текст: "a", язык: "en")]
    let первый = try Поиск.выполнить(вход(узлы: узлы, рёбра: рёбра, словарь: словарь))
    let второй = try Поиск.выполнить(вход(узлы: Array(узлы.reversed()), рёбра: Array(рёбра.reversed()), словарь: Array(словарь.reversed())))
    XCTAssertEqual(первый, второй)
    guard case .кандидат(let кандидат) = первый else { return XCTFail("Нет кандидата") }
    XCTAssertEqual(кандидат.рёбра, ["a"])
    XCTAssertEqual(кандидат.сегменты.map(\.слово), ["a"])
  }

  func test_НеполнотаОтказыИПределы() throws {
    let узлы: [Поиск.Узел] = [.init("s", 0), .init("f", 1)]
    let ребро: [Поиск.Ребро] = [.init("e", из: "s", в: "f", символ: "x", вес: 0)]
    let словарь: [Поиск.Слово] = [.init("w", фонемы: ["x"], текст: "x", язык: "ru")]
    XCTAssertEqual(try Поиск.выполнить(вход(узлы: [], рёбра: [], словарь: [], полный: false)), .неизвестно)
    XCTAssertThrowsError(try Поиск.выполнить(вход(узлы: узлы, рёбра: ребро, словарь: словарь), пределОпераций: 1)) {
      XCTAssertEqual($0 as? Поиск.Ошибка, .пределРесурсов)
    }
    let пустое = [Поиск.Слово("w", фонемы: [], текст: "", язык: "ru")]
    XCTAssertThrowsError(try Поиск.выполнить(вход(узлы: узлы, рёбра: ребро, словарь: пустое)))
    let цикл = [Поиск.Ребро("e", из: "f", в: "s", символ: "x", вес: 0)]
    XCTAssertThrowsError(try Поиск.выполнить(вход(узлы: узлы, рёбра: цикл, словарь: словарь)))
    let нет = [Поиск.Слово("w", фонемы: ["y"], текст: "y", язык: "ru")]
    XCTAssertEqual(try Поиск.выполнить(вход(узлы: узлы, рёбра: ребро, словарь: нет)), .нетСовпадения)
  }

  func test_ПереполнениеНеСтановитсяРезультатом() throws {
    let данные = вход(
      узлы: [.init("s", 0), .init("m", 1), .init("f", 2)],
      рёбра: [.init("a", из: "s", в: "m", символ: "x", вес: Int64.max),
               .init("b", из: "m", в: "f", символ: "y", вес: 1)],
      словарь: [.init("w", фонемы: ["x", "y"], текст: "xy", язык: "ru")])
    XCTAssertThrowsError(try Поиск.выполнить(данные)) { XCTAssertEqual($0 as? Поиск.Ошибка, .переполнение) }
  }

  func test_НесовпавшаяФонемаНеСкладываетСвойВес() throws {
    let данные = вход(
      узлы: [.init("s", 0), .init("m", 1), .init("f", 2)],
      рёбра: [.init("a", из: "s", в: "m", символ: "x", вес: Int64.max),
               .init("отказ", из: "m", в: "f", символ: "z", вес: 1),
               .init("подходит", из: "m", в: "f", символ: "y", вес: 0)],
      словарь: [.init("w", фонемы: ["x", "y"], текст: "xy", язык: "ru")])
    guard case .кандидат(let кандидат) = try Поиск.выполнить(данные) else { return XCTFail("Нет кандидата") }
    XCTAssertEqual(кандидат.оценка, Int64.max)
    XCTAssertEqual(кандидат.рёбра, ["a", "подходит"])
  }

  func test_ПриРавенствеВыбираютсяБайтыАНеНормализованныйUnicode() throws {
    let составной = "é"
    let раздельный = "e\u{301}"
    let узлы: [Поиск.Узел] = [.init("s", 0), .init("f", 1)]
    let рёбра: [Поиск.Ребро] = [
      .init(составной, из: "s", в: "f", символ: "x", вес: 0),
      .init(раздельный, из: "s", в: "f", символ: "x", вес: 0)
    ]
    let словарь: [Поиск.Слово] = [.init("w", фонемы: ["x"], текст: "x", язык: "ru")]
    let первый = try Поиск.выполнить(вход(узлы: узлы, рёбра: рёбра, словарь: словарь))
    let второй = try Поиск.выполнить(вход(узлы: узлы, рёбра: Array(рёбра.reversed()), словарь: словарь))
    guard case .кандидат(let один) = первый, case .кандидат(let два) = второй else { return XCTFail("Нет кандидата") }
    XCTAssertEqual(Array(один.рёбра[0].utf8), Array(раздельный.utf8))
    XCTAssertEqual(Array(два.рёбра[0].utf8), Array(раздельный.utf8))
    XCTAssertNotEqual(Поиск.Узел(составной, 1), Поиск.Узел(раздельный, 1))
    XCTAssertNotEqual(
      Поиск.Ребро(составной, из: "s", в: "f", символ: "x", вес: 0),
      Поиск.Ребро(раздельный, из: "s", в: "f", символ: "x", вес: 0))
    XCTAssertNotEqual(
      Поиск.Слово("w", фонемы: [составной], текст: "x", язык: "ru"),
      Поиск.Слово("w", фонемы: [раздельный], текст: "x", язык: "ru"))
  }

  func test_ПослеКонцаИТупикНеСчитаютсяЧастьюПути() throws {
    let данные = вход(
      узлы: [.init("s", 0), .init("m", 1), .init("f", 2), .init("тупик", 2), .init("после", 3)],
      рёбра: [.init("a", из: "s", в: "m", символ: "x", вес: Int64.max),
               .init("b", из: "m", в: "f", символ: "y", вес: 0),
               .init("тупик", из: "m", в: "тупик", символ: "y", вес: 1),
               .init("после", из: "f", в: "после", символ: "x", вес: 1)],
      словарь: [.init("w", фонемы: ["x", "y"], текст: "xy", язык: "ru"),
                .init("x", фонемы: ["x"], текст: "x", язык: "en")])
    guard case .кандидат(let кандидат) = try Поиск.выполнить(данные) else { return XCTFail("Нет пути") }
    XCTAssertEqual(кандидат.оценка, Int64.max)
    XCTAssertEqual(кандидат.рёбра, ["a", "b"])
  }
}

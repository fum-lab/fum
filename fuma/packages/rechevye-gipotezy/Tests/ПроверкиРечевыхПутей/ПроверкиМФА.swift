@Test func необязательныйЯзыкИЕгоБайтыНеПодменяются() throws {
  let безЯзыка = ПоискРечевыхПутей.Слово("слово", фонемы: ["ʃ"], текст: "пример")
  let безЯзыкаПовтор = ПоискРечевыхПутей.Слово("слово", фонемы: ["ʃ"], текст: "пример")
  let пустаяМетка = ПоискРечевыхПутей.Слово("слово", фонемы: ["ʃ"], текст: "пример", язык: "")
  let составной = ПоискРечевыхПутей.Слово("слово", фонемы: ["ʃ"], текст: "пример", язык: "é")
  let раздельный = ПоискРечевыхПутей.Слово("слово", фонемы: ["ʃ"], текст: "пример", язык: "e\u{301}")
  #expect(безЯзыка == безЯзыкаПовтор)
  #expect(безЯзыка != пустаяМетка)
  #expect(составной != раздельный)

  func результат(_ слово: ПоискРечевыхПутей.Слово) throws -> ПоискРечевыхПутей.Результат {
    try ПоискРечевыхПутей.выполнить(.init(
      полный: true, начало: "s", конец: "f", узлы: [.init("s", 0), .init("f", 1)],
      рёбра: [.init("фонема", из: "s", в: "f", символ: "ʃ", вес: 0)], словарь: [слово]
    ))
  }
  #expect(try результат(безЯзыка) == результат(безЯзыкаПовтор))
  #expect(try результат(составной) != результат(раздельный))
}

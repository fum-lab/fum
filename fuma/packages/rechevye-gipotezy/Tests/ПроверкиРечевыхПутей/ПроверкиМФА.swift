@Test func единицаМФАИВыборИзАльтернативБезВыбораЯзыка() throws {
  let единицаМФА = "t\u{0361}ʃ"
  #expect(единицаМФА.unicodeScalars.count == 3)
  let данные = ПоискРечевыхПутей.Вход(
    полный: true, начало: "s", конец: "f",
    узлы: [.init("s", 0), .init("f", 160)],
    рёбра: [
      .init("фонема", из: "s", в: "f", символ: единицаМФА, вес: -8),
      .init("другая-гипотеза", из: "s", в: "f", символ: "ʃ", вес: -1)
    ],
    словарь: [.init("слово", фонемы: [единицаМФА], текст: "пример")]
  )
  let результат = try ПоискРечевыхПутей.выполнить(данные)
  #expect(данные.рёбра.count == 2)
  guard case .кандидат(let кандидат) = результат else {
    Issue.record("Ожидался путь из сохранённой альтернативы")
    return
  }
  #expect(кандидат.рёбра == ["фонема"])
  #expect(кандидат.оценка == -8)
  #expect(кандидат.сегменты.count == 1)
  let сегмент = try #require(кандидат.сегменты.first)
  #expect(сегмент.язык == nil)
}


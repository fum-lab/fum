import ОтветыКоординатору

/// Место для будущего независимого полномочия; открытой фабрики сейчас нет.
/// Контекст Routine, план и декодированная привязка не создают это полномочие.
public struct ПроверенноеПолномочиеСохраненияМанифеста: Sendable {
    private init() {}
}

public enum ИсходПроверенногоСохранения: Equatable, Sendable {
    case неизвестно(причина: String)
}

/// Адресный вход для плана Routine. Запрос не принимает произвольные argv.
/// Поставщик может проводить свои отдельно разрешённые preflight-чтения до вызова.
/// Пока проверенного issuer и привязки точного сохранения нет, путь закрыт до
/// КомандноеИсполнениеОператора.выполнить и до разбора защищаемых аргументов.
public enum ПроверенныйВходСохраненияМанифеста {
    public static func сохранить(
        план: ПланОтветаКоординатору,
        текущийКонтекст: КонтекстВосстановленияПрофиля,
        полномочие: ПроверенноеПолномочиеСохраненияМанифеста?
    ) -> ИсходПроверенногоСохранения {
        сохранить(план: план, текущийКонтекст: текущийКонтекст,
                  полномочие: полномочие, защищаемыйВызов: {})
    }

    /// Общий отказной путь доступен своему модулю и тестам через `@testable`.
    static func сохранить(
        план: ПланОтветаКоординатору,
        текущийКонтекст: КонтекстВосстановленияПрофиля,
        полномочие: ПроверенноеПолномочиеСохраненияМанифеста?,
        защищаемыйВызов: () -> Void
    ) -> ИсходПроверенногоСохранения {
        _ = план
        _ = текущийКонтекст
        _ = полномочие
        _ = защищаемыйВызов
        // Нет доказанной операции записи точного манифеста в legacy executor.
        // Контейнерная квитанция не является квитанцией этого эффекта.
        return .неизвестно(причина: "Не подтверждены доверенное полномочие и точная привязка сохранения манифеста")
    }
}

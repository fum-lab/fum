    let план = try поддельныйПлан()
    #expect(план.командаСохраненияИсходников != nil)
    let исход = ПроверенныйВходСохраненияМанифеста.сохранить(
        план: план, текущийКонтекст: синтетическийКонтекст(), полномочие: nil)

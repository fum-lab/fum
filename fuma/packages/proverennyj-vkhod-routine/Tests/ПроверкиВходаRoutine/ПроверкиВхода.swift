@Test func синтетическийProviderУдерживаетДублиИОтвергаетДрейф() async throws {
    let привязка = try #require(поддельныйПлан().командаСохраненияИсходников)
    let контекст = синтетическийКонтекст(аренда: привязка.арендаДействуетДо)
    let хранилище = СинтетическоеХранилище(удерживатьЗапись: true)
    let провайдер = СинтетическийПроверяющий(образец: привязка, контекст: контекст, хранилище: хранилище)
    let первый = Task { await провайдер.выполнить(привязка: привязка, контекст: контекст) }
    let началось = await хранилище.дождатьсяНачала()
    if !началось {
        await хранилище.продолжить()
        _ = await первый.value
        Issue.record("Фиктивное хранилище не получило вызов в срок")
        return
    }
    let исходВторого = await провайдер.выполнить(привязка: привязка, контекст: контекст)
    await хранилище.продолжить()
    let исходПервого = await первый.value
    let изменённый = синтетическийКонтекст(аренда: привязка.арендаДействуетДо.addingTimeInterval(1))
    let дрейф = await провайдер.выполнить(привязка: привязка, контекст: изменённый)
    let (байты, число) = await хранилище.снимок()
    #expect(исходПервого == .сохранено(Data("{}".utf8)))
    #expect(исходВторого == .неизвестно)
    #expect(дрейф == .неизвестно)
    #expect(байты == Data("{}".utf8))
    #expect(число == 1)
}


// Эти типы существуют только в synthetic тесте. У них нет системного FS и issuer.
private enum СинтетическаяОшибка: Error { case послеЗаписи }
private enum СинтетическийИсход: Equatable, Sendable {
    case сохранено(Data)
    case неизвестно
}

private actor СинтетическоеХранилище {
    private var байты: Data?
    private var счётчик = 0
    private let ошибкаПослеЗаписи: Bool
    private let удерживатьЗапись: Bool
    private var начато = false
    private var ожидательНачала: CheckedContinuation<Bool, Never>?
    private var ожидателиРазрешения: [CheckedContinuation<Void, Never>] = []
    private var разрешено = false

    init(ошибкаПослеЗаписи: Bool = false, удерживатьЗапись: Bool = false) {
        self.ошибкаПослеЗаписи = ошибкаПослеЗаписи
        self.удерживатьЗапись = удерживатьЗапись
    }

    func сохранить(_ привязка: ПривязкаМанифестаДляАдаптера) async throws -> Data {
        счётчик += 1
        if удерживатьЗапись {
            начато = true
            ожидательНачала?.resume(returning: true)
            ожидательНачала = nil
            if !разрешено {
                await withCheckedContinuation { продолжение in
                    ожидателиРазрешения.append(продолжение)
                    Task {
                        try? await Task.sleep(for: .seconds(2))
                        продолжить()
                    }
                }
            }
        }
        байты = привязка.байтыМанифеста
        if ошибкаПослеЗаписи { throw СинтетическаяОшибка.послеЗаписи }
        return привязка.байтыМанифеста
    }

    func снимок() -> (Data?, Int) { (байты, счётчик) }

    func дождатьсяНачала() async -> Bool {
        if начато { return true }
        return await withCheckedContinuation { продолжение in
            ожидательНачала = продолжение
            Task {
                try? await Task.sleep(for: .seconds(2))
                истёкСрокОжидания()
            }
        }
    }

    private func истёкСрокОжидания() {
        ожидательНачала?.resume(returning: false)
        ожидательНачала = nil
    }

    func продолжить() {
        разрешено = true
        let ожидающие = ожидателиРазрешения
        ожидателиРазрешения.removeAll()
        for ожидающий in ожидающие { ожидающий.resume() }
    }
}

/// Проверяет только переданный synthetic образец и хранит историю в памяти теста.
/// Не выдаёт полномочия, не переживает процесс и не является production provider.
private actor СинтетическийПроверяющий {
    private struct Ключ: Hashable { let поручение: UUID; let запрос: UUID }
    private enum Состояние { case выполняется, неизвестно, завершено(Data) }
    private struct Попытка {
        let привязка: ПривязкаМанифестаДляАдаптера
        let контекст: КонтекстВосстановленияПрофиля
        var состояние: Состояние
    }

    private let образец: ПривязкаМанифестаДляАдаптера
    private let контекстОбразца: КонтекстВосстановленияПрофиля
    private let хранилище: СинтетическоеХранилище
    private var попытки: [Ключ: Попытка] = [:]

    init(образец: ПривязкаМанифестаДляАдаптера, контекст: КонтекстВосстановленияПрофиля,
         хранилище: СинтетическоеХранилище) {
        self.образец = образец
        self.контекстОбразца = контекст
        self.хранилище = хранилище
    }

    func выполнить(привязка: ПривязкаМанифестаДляАдаптера,
                   контекст: КонтекстВосстановленияПрофиля) async -> СинтетическийИсход {
        let ключ = Ключ(поручение: привязка.idПоручения, запрос: привязка.idЗапроса)
        if let попытка = попытки[ключ] {
            guard равныеБайты(попытка.привязка, привязка), равныйКонтекст(попытка.контекст, контекст) else { return .неизвестно }
            if case .завершено(let байты) = попытка.состояние { return .сохранено(байты) }
            return .неизвестно
        }
        let sha = SHA256.hash(data: привязка.байтыМанифеста).map { String(format: "%02x", $0) }.joined()
        guard равныеБайты(привязка, образец), равныйКонтекст(контекст, контекстОбразца),
              sha == привязка.sha256Манифеста,
              контекст.наблюдённыйHEAD == привязка.исходныйКоммит,
              контекст.полныйRef == привязка.исходнаяСсылка,
              контекст.исполнитель == привязка.исполнитель,
              контекст.версияСостояния == привязка.ожидаемаяВерсияСостояния,
              контекст.арендаДействуетДо == привязка.арендаДействуетДо,
              контекст.момент < контекст.арендаДействуетДо else { return .неизвестно }
        попытки[ключ] = Попытка(привязка: привязка, контекст: контекст, состояние: .выполняется)
        do {
            let байты = try await хранилище.сохранить(привязка)
            guard байты == привязка.байтыМанифеста else {
                попытки[ключ]?.состояние = .неизвестно
                return .неизвестно
            }
            попытки[ключ]?.состояние = .завершено(байты)
            return .сохранено(байты)
        } catch {
            попытки[ключ]?.состояние = .неизвестно
            return .неизвестно
        }
    }

    private func равныеБайты(_ первая: ПривязкаМанифестаДляАдаптера, _ вторая: ПривязкаМанифестаДляАдаптера) -> Bool {
        guard первая == вторая else { return false }
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys]
        guard let одни = try? кодировщик.encode(первая), let другие = try? кодировщик.encode(вторая), одни == другие else { return false }
        let первые = [первая.путьМанифеста, первая.исходнаяСсылка, первая.исходныйКоммит, первая.исходноеДерево]
        let вторые = [вторая.путьМанифеста, вторая.исходнаяСсылка, вторая.исходныйКоммит, вторая.исходноеДерево]
        return zip(первые, вторые).allSatisfy { Data($0.0.utf8) == Data($0.1.utf8) }
    }

    private func равныйКонтекст(_ первый: КонтекстВосстановленияПрофиля, _ второй: КонтекстВосстановленияПрофиля) -> Bool {
        guard первый == второй else { return false }
        let первые = [первый.физическийW, первый.исполнитель, первый.наблюдённыйHEAD, первый.полныйRef, первый.assignmentPin, первый.sha256Исходника]
        let вторые = [второй.физическийW, второй.исполнитель, второй.наблюдённыйHEAD, второй.полныйRef, второй.assignmentPin, второй.sha256Исходника]
        return zip(первые, вторые).allSatisfy { Data($0.0.utf8) == Data($0.1.utf8) }
    }
}

@Test func синтетическийProviderСохраняетТочныеБайтыОдинРаз() async throws {
    let план = try поддельныйПлан()
    let привязка = try #require(план.командаСохраненияИсходников)
    let контекст = синтетическийКонтекст(аренда: привязка.арендаДействуетДо)
    let хранилище = СинтетическоеХранилище()
    let провайдер = СинтетическийПроверяющий(образец: привязка, контекст: контекст, хранилище: хранилище)
    let первый = await провайдер.выполнить(привязка: привязка, контекст: контекст)
    let повтор = await провайдер.выполнить(привязка: привязка, контекст: контекст)
    let (байты, число) = await хранилище.снимок()
    #expect(первый == .сохранено(Data("{}".utf8)))
    #expect(повтор == первый)
    #expect(байты == Data("{}".utf8))
    #expect(число == 1)
    // Тот же план через production entry остаётся UNKNOWN.
    #expect(ПроверенныйВходСохраненияМанифеста.сохранить(
        план: план, текущийКонтекст: контекст, полномочие: nil)
        == .неизвестно(причина: "Не подтверждены доверенное полномочие и точная привязка сохранения манифеста"))
}


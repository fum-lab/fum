"""Создать пакет из закреплённых открытых данных в отдельном каталоге вне Git."""

import argparse
import hashlib
import json
import importlib.metadata
from pathlib import Path
import time
import unicodedata

from документы import собрать_документ
from презентации import собрать_презентацию, шрифты
from смета import сумма_закупки, рубли
from таблица import собрать_таблицу


def проверить_имена(презентации):
    занято = {имя.casefold() for имя in ["FUMA-видение-продукта", "FUMA-бизнес-план", "FUMA-сравнение-форм-НКО", "FUMA-протокол-и-анкета", "FUMA-устав-АНО", "FUMA-оборудование", "FUMA-финансовая-модель"]}
    for презентация in презентации:
        имя = презентация["файл"]
        if not isinstance(имя, str) or not имя.startswith("FUMA-") or not 6 <= len(имя) <= 120 or not all(с.isalnum() or с in "-_" for с in имя):
            raise ValueError("Имя результата должно быть безопасной основой FUMA-… без пути и расширения")
        ключ = unicodedata.normalize("NFC", имя).casefold()
        if ключ in занято:
            raise ValueError("Имена результатов совпадают")
        занято.add(ключ)


def собрать(корень, источник, выход, шрифт, жирный):
    начало = time.perf_counter_ns()
    корень = корень.resolve(strict=True)
    источник = источник.resolve(strict=True)
    источник.relative_to(корень)
    данные = json.loads(источник.read_text(encoding="utf-8"))
    if данные.get("схема") != "fuma.пакет-представлений.1":
        raise ValueError("Неизвестная схема пакета")
    проверить_имена(данные["презентации"])
    if len(данные["смета"]["позиции"]) != 7:
        raise ValueError("Первая версия таблицы требует семь фиксированных строк сметы")
    сумма_закупки(данные["смета"]["позиции"])
    хэши = {}
    for путь in [*данные["входы"], str(источник.relative_to(корень))]:
        файл = корень / путь
        файл.resolve(strict=True).relative_to(корень)
        if any(п.is_symlink() for п in [файл, *файл.parents] if п != корень.parent):
            raise ValueError("Символическая ссылка во входе")
        хэши[путь] = hashlib.sha256(файл.read_bytes()).hexdigest()
    выход = выход.resolve()
    if выход.exists():
        raise ValueError("Выберите новый каталог результата; существующий не перезаписывается")
    if any((предок / ".git").exists() for предок in [выход, *выход.parents]):
        raise ValueError("Бинарные результаты сохраняются вне Git")
    шрифты(шрифт, жирный)
    выход.mkdir(parents=True)
    этапы = {}
    отсчёт = time.perf_counter_ns()
    представления = [собрать_презентацию(данные, п, выход) for п in данные["презентации"]]
    этапы["презентации"] = time.perf_counter_ns() - отсчёт
    отсчёт = time.perf_counter_ns()
    имена = {
        "Документация/видение-продукта-FUMA.md": "FUMA-видение-продукта",
        "Планирование/финансирование-и-ресурсы/бизнес-план-FUMA.md": "FUMA-бизнес-план",
        "Планирование/финансирование-и-ресурсы/НКО-Крым/сравнение-форм.md": "FUMA-сравнение-форм-НКО",
        "Планирование/финансирование-и-ресурсы/НКО-Крым/протокол-и-анкета.md": "FUMA-протокол-и-анкета",
    }
    for исходник, имя in имена.items():
        собрать_документ(корень / исходник, выход / имя)
    этапы["документы"] = time.perf_counter_ns() - отсчёт
    отсчёт = time.perf_counter_ns()
    собрать_таблицу(данные["смета"], выход / "FUMA-финансовая-модель.xlsx")
    этапы["таблица"] = time.perf_counter_ns() - отсчёт
    файлы = [{"путь": str(п.relative_to(выход)), "байт": п.stat().st_size, "sha256": hashlib.sha256(п.read_bytes()).hexdigest()}
             for п in sorted(выход.iterdir()) if п.is_file()]
    результат = {
        "схема": "fuma.пакет-представлений-результат.1", "дата_данных": данные["дата"], "входы_sha256": хэши,
        "представления": представления, "файлы": файлы,
        "смета": {"капитальные_расходы_RUB": сумма_закупки(данные["смета"]["позиции"]),
                  "подписка_RUB_месяц": рубли(данные["смета"]["подписка_USD_месяц"], данные["смета"]["курс_USD_RUB"])},
        "наносекунды": time.perf_counter_ns() - начало,
        "этапы_наносекунды": этапы,
        "код_sha256": {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in sorted(Path(__file__).parent.glob("*.py"))},
        "зависимости": {имя: importlib.metadata.version(имя) for имя in ["python-pptx", "python-docx", "reportlab", "openpyxl"]},
        "граница": "Создание документов из локальных данных; без сети и отправки. Содержание воспроизводимо; побайтная идентичность ZIP/DOCX не заявлена.",
        "шрифты_sha256": [hashlib.sha256(шрифт.read_bytes()).hexdigest(), hashlib.sha256(жирный.read_bytes()).hexdigest()],
    }
    (выход / "манифест.json").write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    строки = ["# Пакет FUMA", "", "Подготовительные материалы от " + данные["дата"] + ". Заявки не поданы, суммы и партнёрства не согласованы.", "", "## Презентации", ""]
    for п in представления:
        строки.append("- " + п["название"] + ": [PDF](" + п["файл"] + ".pdf), [PPTX](" + п["файл"] + ".pptx).")
    строки += ["", "## Документы", ""]
    for имя in имена.values():
        строки.append("- [" + имя + "](" + имя + ".docx): [PDF](" + имя + ".pdf).")
    строки += ["", "- [Финансовая модель](FUMA-финансовая-модель.xlsx). Пустые жёлтые поля требуют исходных данных; зелёные содержат формулы.", "", "## Условия сборки", "", "PDF использует указанный при сборке системный Arial. Права на шрифт не заменяются лицензией CC0 исходников FUM. Для переноса можно передать совместимые TTF с кириллицей."]
    (выход / "README.md").write_text("\n".join(строки) + "\n", encoding="utf-8")
    return {"каталог": str(выход), "презентаций": len(представления), "файлов": len(файлы) + 2,
            "секунд": round(результат["наносекунды"] / 1e9, 3)}


def главная():
    аргументы = argparse.ArgumentParser()
    аргументы.add_argument("--корень", type=Path, required=True)
    аргументы.add_argument("--данные", type=Path, required=True)
    аргументы.add_argument("--выход", type=Path, required=True)
    аргументы.add_argument("--шрифт", type=Path, required=True)
    аргументы.add_argument("--жирный-шрифт", type=Path, required=True)
    вход = аргументы.parse_args()
    print(json.dumps(собрать(вход.корень, вход.данные, вход.выход, вход.шрифт, вход.жирный_шрифт), ensure_ascii=False))


if __name__ == "__main__":
    главная()

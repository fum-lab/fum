"""Редактируемая смета: пустые исходные данные не превращаются в нулевой бюджет."""

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.worksheet.datavalidation import DataValidation


def собрать_таблицу(данные, выход):
    книга = Workbook()
    параметры = книга.active
    параметры.title = "Параметры"
    параметры.append(["FUMA · исходные данные и расчёт · подготовительная версия"])
    параметры.append(["Показатель", "Значение", "Основание / как заполнить"])
    строки = [
        ["Горизонт, месяцев", данные["горизонт_месяцев"], "Изменяемый горизонт плана; по умолчанию 12"],
        ["Курс RUB за USD", данные["курс_USD_RUB"], "Фактическая стоимость оплаты; источник и дата обязательны"],
        ["ChatGPT Pro 20X, USD/месяц", данные["подписка_USD_месяц"], "Ориентир 200 USD; действующие условия и счёт перепроверяются"],
        ["Подписка, RUB/месяц", '=IF(COUNT(B4:B5)=2,B4*B5,"")', "Дополнительные налоги/комиссии при необходимости отдельно"],
        ["Остальные расходы, RUB/месяц", None, "Труд, API, электричество, связь, налоги, сопровождение; 0 только если подтверждён"],
        ["Всего операционных, RUB/месяц", '=IF(COUNT(B6:B7)=2,SUM(B6:B7),"")', "Не считается при неизвестном курсе или расходах"],
        ["Резерв капитальных расходов, доля", данные["резерв_доля"], данные["резерв_основание"]],
        ["Разовые организационные расходы, RUB", None, "Регистрация, подпись, нотариус и иное по выбранному маршруту"],
        ["Собственные средства, RUB", None, "Только действительное доступное участие"],
        ["Подтверждённая поддержка, RUB", None, "Без кредита; гранты и пожертвования лишь при подтверждении"],
        ["Планируемый кредит, RUB", None, "Не является одобренным лимитом"],
        ["Годовая ставка, доля", None, "Введите ставку выбранного сценария; 20% = 0,20"],
        ["Срок кредита, месяцев", 36, "Расчётный пример срока; условие банка ещё не выбрано"],
        ["Аннуитетный платёж, RUB/месяц", '=IF(ISNUMBER(B13),IF(B13=0,0,IF(COUNT(B14:B15)=2,IF(B14=0,B13/B15,-PMT(B14/12,B15,B13)),"")),"")', "Ориентир без комиссий, отсрочек и особенностей графика банка"],
        ["Денежный поток до долга, RUB/месяц", None, "Требует обоснования поступлений, налогов и расходов"],
        ["Покрытие долга", '=IF(AND(COUNT(B16:B17)=2,B16>0),B17/B16,"")', "Порог банка не задан; пусто при неизвестном потоке"],
        ["", None, ""],
        ["Капитальные расходы, RUB", '=IF(ISNUMBER(Смета!E13),Смета!E13,"")', "Сумма выбранных позиций"],
        ["Капитальный резерв, RUB", '=IF(COUNT(B9,B20)=2,B9*B20,"")', "Резерв не означает уже оплаченные расходы"],
        ["Бюджет за горизонт, RUB", '=IF(COUNT(B20,B21,B8,B3,B10)=5,B20+B21+B8*B3+B10,"")', "Полный бюджет до выбора источников финансирования"],
        ["Дефицит без долга, RUB", '=IF(COUNT(B22,B11,B12)=3,MAX(0,B22-B11-B12),"")', "Потребность не равна автоматически допустимой сумме кредита"],
        ["Подписка за горизонт, USD", '=IF(COUNT(B3,B5)=2,B3*B5,"")', "При 12 месяцах: 2400 USD, без конвертации и доплат"],
    ]
    for строка in строки:
        параметры.append(строка)
    параметры["B9"].number_format = параметры["B14"].number_format = "0.0%"

    смета = книга.create_sheet("Смета")
    смета.append(["Оборудование · RUB · выбранные позиции"])
    смета.append(["Синие поля редактируются; пустая цена выбранной позиции блокирует итог."])
    смета.append(["Mac Studio, RTX Spark и DGX Spark включены по отдельным поручениям пользователя."])
    смета.append(["Позиция", "Кол-во", "Цена RUB", "Статус", "Сумма RUB", "Источник"])
    for номер, позиция in enumerate(данные["позиции"], 5):
        смета.append([позиция["название"], позиция["количество"], позиция["цена"], позиция["статус"],
                      f'=IF(ISNUMBER(B{номер}),IF(B{номер}=0,0,IF(ISNUMBER(C{номер}),B{номер}*C{номер},"")),"")', позиция["источник"]])
        if позиция["источник"]:
            смета.cell(номер, 6).hyperlink = позиция["источник"]
    смета["A13"] = "Всего по выбранным позициям"
    смета["E13"] = '=IF(COUNT(E5:E11)=ROWS(E5:E11),SUM(E5:E11),"")'
    смета["A15"] = "Отсутствующая цена не означает нулевую цену. Веб-цена DGX не заменяет коммерческое предложение."

    потоки = книга.create_sheet("Денежный поток")
    потоки.append(["Помесячная модель первого года · RUB"])
    потоки.append(["Начальный остаток после оборудования и разовых расходов",
                   '=IF(COUNT(Параметры!B11:B13,Параметры!B20,Параметры!B10)=5,SUM(Параметры!B11:B13)-Параметры!B20-Параметры!B10,"")'])
    потоки.append(["Месяц", "Поступления", "Операционные расходы", "Платёж по долгу", "Чистый поток", "Остаток денег"])
    for месяц in range(1, 13):
        строка = месяц + 3
        предыдущий = "B2" if месяц == 1 else f"F{строка-1}"
        потоки.append([месяц, None, '=IF(ISNUMBER(Параметры!B8),Параметры!B8,"")',
                       f'=IF(COUNT(Параметры!B15:B16)=2,IF(A{строка}<=Параметры!B15,Параметры!B16,0),"")',
                       f'=IF(COUNT(B{строка}:D{строка})=3,B{строка}-C{строка}-D{строка},"")',
                       f'=IF(COUNT({предыдущий},E{строка})=2,{предыдущий}+E{строка},"")'])
    потоки["A18"] = "Поступления заполняются по месяцам с основаниями. Не подтверждённые гранты и пожертвования не включаются в базу."
    потоки["A19"] = "Резерв остаётся деньгами до использования. Комиссии и иные платежи банка добавляются к фактическим расходам."

    сценарии = книга.create_sheet("Сценарии")
    сценарии.append(["Сценарии чувствительности · множители — допущения, не прогноз"])
    сценарии.append(["Сценарий", "CAPEX ×", "OPEX ×", "Сравнимый бюджет RUB", "Пояснение"])
    for номер, (название, капитальный, текущий, пояснение) in enumerate([
        ("Базовый", 1, 1, "Только обоснованные исходные данные"),
        ("Рост расходов", 1.2, 1.25, "Проверка чувствительности к поставке и эксплуатации"),
        ("Задержка доходов", 1, 1, "Дублируйте денежный поток и переносите реальные поступления; бюджет от задержки не уменьшается"),
    ], 3):
        сценарии.append([название, капитальный, текущий,
                         f'=IF(COUNT(Параметры!B20:B21,Параметры!B8,Параметры!B3,Параметры!B10)=5,(Параметры!B20+Параметры!B21)*B{номер}+Параметры!B8*Параметры!B3*C{номер}+Параметры!B10,"")', пояснение])

    for лист in книга:
        лист.freeze_panes = "B4"
        лист.sheet_view.showGridLines = False
        лист.column_dimensions["A"].width = 57
        for колонка in "BCDEF":
            лист.column_dimensions[колонка].width = 25 if колонка != "C" or лист != параметры else 90
        for строка in лист:
            for ячейка in строка:
                ячейка.alignment = Alignment(vertical="top", wrap_text=True)
                ячейка.font = Font(name="Arial", size=11, color="172E40")
                if ячейка.data_type == "f":
                    ячейка.fill = PatternFill("solid", fgColor="E4EED9")
                    ячейка.number_format = '#,##0.00;[Red]-#,##0.00'
            лист.row_dimensions[строка[0].row].height = 42
        лист.row_dimensions[1].height = 45
        for ячейка in лист[1]:
            ячейка.fill = PatternFill("solid", fgColor="102436")
            ячейка.font = Font(name="Arial", size=14, bold=True, color="FFFFFF")
    for строка in [3, 4, 5, 7, 9, 10, 11, 12, 13, 14, 15, 17]:
        параметры.cell(строка, 2).font = Font(name="Arial", size=11, color="1768A6")
        if параметры.cell(строка, 2).value is None:
            параметры.cell(строка, 2).fill = PatternFill("solid", fgColor="FFF1BF")
    параметры["B9"].number_format = параметры["B14"].number_format = "0.0%"
    for номер in range(5, 12):
        for колонка in [2, 3]:
            смета.cell(номер, колонка).font = Font(name="Arial", size=11, color="1768A6")
        if смета.cell(номер, 3).value is None:
            смета.cell(номер, 3).fill = PatternFill("solid", fgColor="FFF1BF")
    проверка = DataValidation(type="decimal", operator="greaterThanOrEqual", formula1=0, allow_blank=True)
    проверка.errorTitle, проверка.error = "Недопустимое значение", "Введите неотрицательное число"
    проверка.showErrorMessage = True
    проверка.errorStyle = "stop"
    параметры.add_data_validation(проверка)
    for строка in [5, 7, 9, 10, 11, 12, 13, 14]:
        проверка.add(f"B{строка}")
    курс = DataValidation(type="decimal", operator="greaterThan", formula1=0, allow_blank=True)
    курс.showErrorMessage = True
    курс.errorStyle = "stop"
    курс.error = "Введите положительный валютный курс"
    параметры.add_data_validation(курс)
    курс.add("B4")
    цены = DataValidation(type="decimal", operator="greaterThanOrEqual", formula1=0, allow_blank=True)
    цены.showErrorMessage = True
    цены.errorStyle = "stop"
    смета.add_data_validation(цены)
    цены.add("B5:C11")
    срок = DataValidation(type="whole", operator="greaterThanOrEqual", formula1=1, allow_blank=False)
    срок.showErrorMessage = True
    параметры.add_data_validation(срок)
    срок.add("B3")
    срок.add("B15")
    книга.save(выход)

    private func событие(порядок: Int, идентификатор: String) -> String {
        "{\"порядок\":\(порядок),\"идентификатор\":\"\(идентификатор)\",\"корневойUUID\":\"\(корневойUUID)\",\"время\":\"2026-10-29T00:00:00Z\",\"вид\":\"test\",\"свидетельство\":\"fixture\"}"
    }

    private func завершённаяЗапись(_ значение: String) -> Data {
        Data((значение + "\n").utf8)
    }

    private func объединитьЗаписи(_ записи: [Data]) -> Data {
        записи.reduce(into: Data()) { итог, запись in
            итог.append(запись)
        }
    }

    private func синтетическиеЗаписи(число: Int) -> Data {
        var байты = Data()
        for номер in 0..<число {
            let строка = событие(порядок: номер, идентификатор: "событие-\(номер)")
            байты.append(Data((строка + "\n").utf8))
        }
        return байты
    }

    private func разобратьJSONЗаписи(_ байты: Data) throws -> Int {
        var индекс = байты.startIndex
        var число = 0
        while индекс < байты.endIndex {
            guard let индексLF = байты[индекс..<байты.endIndex].firstIndex(of: 0x0a) else { break }
            let тело = Data(байты[индекс..<индексLF])
            _ = try JSONSerialization.jsonObject(with: тело)
            индекс = байты.index(after: индексLF)
            число += 1
        }
        return число
    }

    private func хешироватьJSONЗаписи(_ байты: Data) -> UInt8 {
        var индекс = байты.startIndex
        var проверочныйБайт: UInt8 = 0
        while индекс < байты.endIndex {
            guard let индексLF = байты[индекс..<байты.endIndex].firstIndex(of: 0x0a) else { break }
            let тело = Data(байты[индекс..<индексLF])
            проверочныйБайт ^= Array(SHA256.hash(data: тело)).first ?? 0
            индекс = байты.index(after: индексLF)
        }
        return проверочныйБайт
    }

    private func измеритьНаносекунды(_ операция: () throws -> Void) rethrows -> Int64 {
        let начало = ProcessInfo.processInfo.systemUptime
        try операция()
        return Int64((ProcessInfo.processInfo.systemUptime - начало) * 1_000_000_000)
    }

    @Test("синтетический профиль N, 2N и 4N разделяет чтение, разбор и хеширование")
    func синтетическийПрофильЧтенияРазбораИХеширования() throws {
        let каталог = FileManager.default.temporaryDirectory
            .appendingPathComponent("fum-koordinaciya-jsonl-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: каталог) }

        var измерения: [[String: Any]] = []
        for числоЗаписей in [256, 512, 1024] {
            let файл = каталог.appendingPathComponent("данные-\(числоЗаписей).jsonl")
            try синтетическиеЗаписи(число: числоЗаписей).write(to: файл, options: .atomic)

            var прочитанныеБайты = Data()
            let чтениеНС = try измеритьНаносекунды {
                прочитанныеБайты = try Data(contentsOf: файл)
            }

            var числоJSONЗаписей = 0
            let разборНС = try измеритьНаносекунды {
                числоJSONЗаписей = try разобратьJSONЗаписи(прочитанныеБайты)
            }

            var контрольныйБайтХеша: UInt8 = 0
            let хешированиеНС = измеритьНаносекунды {
                контрольныйБайтХеша = хешироватьJSONЗаписи(прочитанныеБайты)
            }

            var числоСобытийЧитателя = 0
            var состояниеЧитателя = СостояниеЖурналаJSONL.повреждён
            let полныйПроходНС = измеритьНаносекунды {
                let результат = ЧтениеЖурналаJSONL.разобрать(
                    байты: прочитанныеБайты,
                    ожидаемыйКорневойUUID: корневойUUID
                )
                числоСобытийЧитателя = результат.события.count
                состояниеЧитателя = результат.состояние
            }

            #expect(прочитанныеБайты.count <= 2_000_000)
            #expect(числоЗаписей <= 4096)
            #expect(числоJSONЗаписей == числоЗаписей)
            #expect(числоСобытийЧитателя == числоЗаписей)
            #expect(состояниеЧитателя == .полный)
            измерения.append([
                "числоЗаписей": числоЗаписей,
                "числоБайт": прочитанныеБайты.count,
                "чтениеНаносекунды": чтениеНС,
                "разборJSONНаносекунды": разборНС,
                "хешированиеНаносекунды": хешированиеНС,
                "полныйПроходНаносекунды": полныйПроходНС,
                "контрольныйБайтХеша": Int(контрольныйБайтХеша)
            ])
        }
        let отчёт = try JSONSerialization.data(
            withJSONObject: ["схема": "fum.координация.профиль-jsonl.1", "измерения": измерения],
            options: [.sortedKeys]
        )
        print(String(decoding: отчёт, as: UTF8.self))
    }


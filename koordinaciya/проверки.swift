        проверить("acceptance не становится применением", принято.решенияИсточников.first?.решение == .принятоЖдётОбратногоСлияния)
        let применено = ОценщикСамообновления.оценить(планСамообновления(переходСамообновления(обзорВыполнен: true, принято: true, слияниеВыполнено: true)))

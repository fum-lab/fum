        проверить("21 GiB допускает лёгкий source-only checkpoint без старого 55-GiB порога", ОценщикСамообновления.оценитьРесурсныйДопуск(свободноГиБ: 21, минимальныйРезервДляТяжёлойПроверкиГиБ: nil, тяжёлаяПроверка: false))
        проверить("тяжёлая проверка требует свежую scoped оценку резерва", !ОценщикСамообновления.оценитьРесурсныйДопуск(свободноГиБ: 21, минимальныйРезервДляТяжёлойПроверкиГиБ: nil, тяжёлаяПроверка: true) && ОценщикСамообновления.оценитьРесурсныйДопуск(свободноГиБ: 21, минимальныйРезервДляТяжёлойПроверкиГиБ: 20, тяжёлаяПроверка: true))

        print("Проверок: \(числоПроверок); отказов: \(ошибки)")
        if ошибки != 0 {
            exit(EXIT_FAILURE)
        }
    }

import Foundation

@main
struct ПроверкиКоординатора {
    static func main() {
        var ошибки = 0

        func проверить(_ имя: String, _ условие: @autoclosure () -> Bool) {
            if условие() {
                print("УСПЕХ: \(имя)")
            } else {
                fputs("ОТКАЗ: \(имя)\n", stderr)
                ошибки += 1
            }
        }

        let текущаяОснова = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
        let стараяОснова = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"

        func пакет(
            идентификатор: String = "PR-test",
            состояние: String = "open",
            основание: String = текущаяОснова,
            черновик: Bool? = false,
            сходимость: Bool? = true,
            обзор: String = "пройден",
            грязныйИсточник: Bool = false,
            препятствия: [String] = [],
            пути: [String]? = nil,
            файловИзменено: Int = 2,
            ожидаетсяФайлов: Int = 2,
            принятоКорнем: Bool = false,
            коммитПриёмки: String? = nil,
            установкаГотова: Bool = false,
            вид: String = "запрос-на-слияние",
            слито: Bool = false
        ) -> ПакетПоставки {
            let выбранныеПути = пути ?? (0..<файловИзменено).map { "файл-\($0).json" }
            return ПакетПоставки(
                идентификатор: идентификатор,
                вид: вид,
                номер: вид == "запрос-на-слияние" ? 999 : nil,
                состояние: состояние,
                слито: слито,
                черновик: черновик,
                сходимость: сходимость,
                основание: основание,
                голова: "1111111111111111111111111111111111111111",
                дерево: "2222222222222222222222222222222222222222",
                родители: ["3333333333333333333333333333333333333333"],
                пути: выбранныеПути,
                файловИзменено: файловИзменено,
                ожидаетсяФайлов: ожидаетсяФайлов,
                обзор: обзор,
                принятоКорнем: принятоКорнем,
                коммитПриёмки: коммитПриёмки,
                грязныйИсточникИспользован: грязныйИсточник,
                установкаГотова: установкаГотова,
                препятствия: препятствия,
                непроверенныеЗаявления: []
            )
        }

        func переход(
            план: Bool? = true,
            отправлено: Bool? = true,
            старт: Bool? = nil,
            применение: Bool? = nil,
            наблюдение: String? = nil,
            свидетельство: String? = nil
        ) -> ПереходСостояния {
            ПереходСостояния(
                идентификатор: "переход-test",
                область: "файловая-система-и-git",
                планПодготовлен: план,
                отправлено: отправлено,
                выполнениеНачато: старт,
                применениеЗаявлено: применение,
                независимыйВывод: наблюдение,
                свидетельствоНезависимогоНаблюдения: свидетельство
            )
        }

        let готовый = Оценщик.оценить(пакет: пакет(), текущаяОснова: текущаяОснова)
        проверить("точный проверенный кандидат допускается к ROOT-приёмке", готовый.решение == .готовКПриёмкеКорнем)

        let устаревший = Оценщик.оценить(пакет: пакет(основание: стараяОснова), текущаяОснова: текущаяОснова)
        проверить("устаревшая основа требует нового кандидата", устаревший.решение == .нуженАктуальныйКандидат)

        let черновик = Оценщик.оценить(пакет: пакет(черновик: true), текущаяОснова: текущаяОснова)
        проверить("черновик остаётся у писателя", черновик.решение == .ожидаетПисателя)

        let безОбзора = Оценщик.оценить(пакет: пакет(обзор: "ожидает"), текущаяОснова: текущаяОснова)
        проверить("непроверенный пакет требует RO-review", безОбзора.решение == .нуженОбзор)

        let грязный = Оценщик.оценить(пакет: пакет(грязныйИсточник: true), текущаяОснова: текущаяОснова)
        проверить("грязный источник закрывается отказом", грязный.решение == .некорректен)

        let неверныйСостав = Оценщик.оценить(
            пакет: пакет(файловИзменено: 3),
            текущаяОснова: текущаяОснова
        )
        проверить("несовпадающий состав путей закрывается отказом", неверныйСостав.решение == .некорректен)

        let повторныйПуть = Оценщик.оценить(
            пакет: пакет(пути: ["a.json", "a.json"]),
            текущаяОснова: текущаяОснова
        )
        проверить("точный манифест с повторным путём закрывается отказом", повторныйПуть.решение == .некорректен)

        let препятствие = Оценщик.оценить(
            пакет: пакет(препятствия: ["P1 route validator"]),
            текущаяОснова: текущаяОснова
        )
        проверить("известное P1 блокирует приёмку", препятствие.решение == .заблокирован)

        let отправленоНеНачато = ОценщикПерехода.оценить(переход())
        проверить("отправленное поручение не считается начатым", отправленоНеНачато.решение == .отправленоОжидаетСтарта)

        let заявленноеБезНаблюдения = ОценщикПерехода.оценить(
            переход(старт: true, применение: true)
        )
        проверить("заявленное применение ждёт независимого наблюдения", заявленноеБезНаблюдения.решение == .применениеОжидаетНаблюдения)

        let подтверждённое = ОценщикПерехода.оценить(
            переход(старт: true, применение: true, наблюдение: "подтверждено", свидетельство: "RO readback")
        )
        проверить("независимое наблюдение подтверждает применение отдельно от запуска", подтверждённое.решение == .применениеПодтверждено)

        let неверныйПорядок = ОценщикПерехода.оценить(
            переход(отправлено: false, старт: true)
        )
        проверить("старт без отправки выявляется", неверныйПорядок.решение == .некорректен)

        let толькоПлан = ОценщикПерехода.оценить(
            переход(отправлено: false)
        )
        проверить("план без отправки остаётся планом", толькоПлан.решение == .планЕщёНеОтправлен)

        let принятаяКонтрольнаяТочка = Оценщик.оценить(
            пакет: пакет(
                идентификатор: "PR440",
                состояние: "closed",
                основание: стараяОснова,
                обзор: "принят-источник",
                препятствия: ["native readers", "completion/recency checkpoint"],
                пути: (0..<13).map { "принято-\($0).json" },
                файловИзменено: 13,
                ожидаетсяФайлов: 13,
                принятоКорнем: true,
                коммитПриёмки: текущаяОснова,
                вид: "запрос-на-слияние",
                слито: true
            ),
            текущаяОснова: текущаяОснова
        )
        проверить("принятая контрольная точка не становится установленной", принятаяКонтрольнаяТочка.решение == .принятоБезУстановки)

        let маршрутИсправляется = Оценщик.оценить(
            пакет: пакет(
                идентификатор: "route-inventory-2a3",
                состояние: "checkpoint",
                черновик: nil,
                сходимость: nil,
                обзор: "нужны-исправления",
                препятствия: ["три P1 route-validator findings; тот же writer исправляет"],
                пути: (0..<11).map { "route-\($0).swift" },
                файловИзменено: 11,
                ожидаетсяФайлов: 11,
                вид: "контрольная-точка"
            ),
            текущаяОснова: текущаяОснова
        )
        проверить("контрольная точка с P1 ждёт того же писателя", маршрутИсправляется.решение == .заблокирован)

        let событие = СобытиеКоординации(
            порядок: 1,
            идентификатор: "событие-1",
            корневойUUID: "01a07d3d-d376-7ad2-aafc-67e4c25a67eb",
            время: "2026-10-28T13:10:42Z",
            вид: "test",
            свидетельство: "ограниченная фикстура",
            исход: nil
        )
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys]
        let строкаСобытия = String(decoding: try! кодировщик.encode(событие), as: UTF8.self) + "\n"
        let корректныйЖурнал = ЖурналКоординации.проверить(
            строки: строкаСобытия,
            корневойUUID: событие.корневойUUID
        )
        проверить("одна полная JSONL-запись принимается", корректныйЖурнал.isEmpty)

        let повтор = ЖурналКоординации.проверить(
            строки: строкаСобытия + строкаСобытия,
            корневойUUID: событие.корневойUUID
        )
        проверить("повторный id события выявляется", повтор.contains("повторный-идентификатор-события"))

        let модельУзла = МодельУзлаКоординации(
            веткаЯвляетсяУзлом: true,
            собственнаяПамять: "koordinaciya",
            дочерниеУзлы: [],
            деревоСодержит: ["собственная-память", "дочерние-узлы"],
            общаяПамять: "только-чтение",
            процесс: "инкарнация",
            полноеДеревоПовтореноВJSON: false,
            последнийКоммитВосстановления: nil
        )
        проверить("описатель узла хранит только память и ссылки на детей", Оценщик.проверитьМодельУзла(модельУзла).isEmpty)

        let нарушеннаяМодель = МодельУзлаКоординации(
            веткаЯвляетсяУзлом: true,
            собственнаяПамять: "../чужая-область",
            дочерниеУзлы: ["child", "child"],
            деревоСодержит: ["полная-копия-дерева"],
            общаяПамять: "запись",
            процесс: "инкарнация",
            полноеДеревоПовтореноВJSON: true,
            последнийКоммитВосстановления: "не-oid"
        )
        проверить("описатель с чужой памятью и сериализованным деревом отклоняется", !Оценщик.проверитьМодельУзла(нарушеннаяМодель).isEmpty)

        let хвост = ЖурналКоординации.проверить(
            строки: String(строкаСобытия.dropLast()),
            корневойUUID: событие.корневойUUID
        )
        проверить("неполный EOF без LF отклоняется", хвост.contains("неполный-JSONL-хвост"))

        let усечённыйМинус = КлассификаторПокрытияПути.оценить(
            СвидетельствоПокрытияПути(путьНайден: false, полноеПокрытие: false, выводУсечён: true)
        )
        проверить("усечённый вывод без совпадения даёт unknown, не absent", усечённыйМинус == .неизвестно)

        let неполныйМинус = КлассификаторПокрытияПути.оценить(
            СвидетельствоПокрытияПути(путьНайден: false, полноеПокрытие: false, выводУсечён: false)
        )
        проверить("неполное покрытие без совпадения остаётся unknown", неполныйМинус == .неизвестно)

        let полныйМинус = КлассификаторПокрытияПути.оценить(
            СвидетельствоПокрытияПути(путьНайден: false, полноеПокрытие: true, выводУсечён: false)
        )
        проверить("отсутствие подтверждается только полным неусечённым обходом", полныйМинус == .отсутствует)

        let положительноеПриУсечении = КлассификаторПокрытияПути.оценить(
            СвидетельствоПокрытияПути(путьНайден: true, полноеПокрытие: false, выводУсечён: true)
        )
        проверить("найденный путь остаётся положительным свидетельством при усечении", положительноеПриУсечении == .найден)

        let полныйПакетПоручений = СнимокПоручений(
            группа: "временная-фикстура",
            числоНазначено: 2,
            числоНаблюдено: 2,
            выводУсечён: false,
            записи: [
                ЗаписьНаблюденияПоручения(имя: "новый-ход", статусХода: "inProgress", времяСтарта: 100, новыйСтарт: true, поручениеПодхвачено: true),
                ЗаписьНаблюденияПоручения(имя: "продолжение", статусХода: "inProgress", времяСтарта: 50, новыйСтарт: false, поручениеПодхвачено: true)
            ]
        )
        let полныйИтогПоручений = ОценщикПоручений.оценить(полныйПакетПоручений)
        проверить("полный пакет различает два запущенных поручения", полныйИтогПоручений.фактическиНачато == 2)
        проверить("новый turn отделён от уже идущего продолжения", полныйИтогПоручений.новыеХоды == 1 && полныйИтогПоручений.продолжённыеХоды == 1)
        проверить("полный список подтверждает нулевое ожидание старта", полныйИтогПоручений.неНачато == 0)

        let усечённыйПакетПоручений = СнимокПоручений(
            группа: "усечённая-фикстура",
            числоНазначено: 2,
            числоНаблюдено: 1,
            выводУсечён: true,
            записи: [
                ЗаписьНаблюденияПоручения(имя: "наблюдённый", статусХода: "inProgress", времяСтарта: 100, новыйСтарт: true, поручениеПодхвачено: true)
            ]
        )
        let усечённыйИтогПоручений = ОценщикПоручений.оценить(усечённыйПакетПоручений)
        проверить("усечённая очередь не выдаёт общий стартовый счёт", !усечённыйИтогПоручений.покрытиеПолное && усечённыйИтогПоручений.фактическиНачато == nil)
        проверить("усечённая очередь сохраняет только доказанный нижний предел", усечённыйИтогПоручений.доказаноИсполняется == 1 && усечённыйИтогПоручений.неНачато == nil)

        let баланс = ОценщикБалансировки.оценить(
            СнимокБалансировки(
                до: БалансУзлов(активные: 4, бездействующие: 7, неЗагруженные: 28, видимые: 39),
                после: БалансУзлов(активные: 12, бездействующие: 3, неЗагруженные: 24, видимые: 39),
                источникСхема: "fum.root.dispatch-program.v1",
                источникSHA256: "34d49ac3f78e21c95bfea7ef09a09a2427cab2529ae78bcd5cf0af7f59a603ae"
            )
        )
        проверить("баланс видимых узлов сохраняется до и после", баланс.сбалансирован)
        проверить("native сверка выводит изменение active/idle/notLoaded", баланс.изменениеАктивных == 8 && баланс.изменениеБездействующих == -4 && баланс.изменениеНезагруженных == -4)

        let пересечение = СверкаГрязныхПутей.пересечения(
            путиПакета: ["doska-obyyavlenij/postanovka.json", "zhurnal/пример.json"],
            точныеГрязныеПути: ["Журнал/README.md", "Журнал/новая-папка/запрос.md"]
        )
        проверить("непересекающиеся ROOT dirty пути не блокируют приёмку пакета", пересечение.isEmpty)
        let точноеСовпадение = СверкаГрязныхПутей.пересечения(
            путиПакета: ["Журнал/README.md"],
            точныеГрязныеПути: ["Журнал/README.md"]
        )
        проверить("точное совпадение пути обнаруживается", точноеСовпадение == ["Журнал/README.md"])

        let манифестНеПолучен = СверкаГрязныхПутей.оценить(
            пакеты: [пакет()],
            точныеГрязныеПути: nil,
            полноеПокрытие: false
        )
        проверить("неполученный манифест dirty paths не равен нулевому пересечению", манифестНеПолучен.count == 1 && !манифестНеПолучен[0].манифестПолный)

        let манифестЧастичный = СверкаГрязныхПутей.оценить(
            пакеты: [пакет()],
            точныеГрязныеПути: ["часть-списка.md"],
            полноеПокрытие: false
        )
        проверить("неполный непустой манифест не доказывает отсутствие пересечений", !манифестЧастичный[0].манифестПолный && манифестЧастичный[0].пересечения.isEmpty)

        print("Проверок: 35; отказов: \(ошибки)")
        if ошибки != 0 {
            exit(EXIT_FAILURE)
        }
    }
}

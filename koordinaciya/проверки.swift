        func планСамообновления(_ переход: ПереходСамообновления) -> ПланСамообновления {
            ПланСамообновления(
                собственныйКонтрольныйКоммит: "27f8230a5d4fcaa7507ddecef499ca6990444fae",
                собственныйРеф: свойРеф,
                собственнаяОбласть: "koordinaciya/**",
                текущаяВерсия: "fum.координация.состояние.3",

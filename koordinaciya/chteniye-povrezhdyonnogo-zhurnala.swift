import CryptoKit
import Foundation

public struct ДиапазонБайтJSONL: Codable, Equatable, Sendable {
    public let начало: Int
    public let конец: Int

    public init(начало: Int, конец: Int) {
        self.начало = начало
        self.конец = конец
    }

    public var длина: Int { конец - начало }
}

public enum СостояниеЖурналаJSONL: String, Codable, Equatable, Sendable {
    case полный
    case повреждён
}

public enum ПричинаПоврежденияЖурналаJSONL: String, Codable, Equatable, Sendable {
    case пустойВход
    case пустаяЗапись
    case некорректныйUTF8
    case запрещённыйCR
    case нулевойБайт
    case некорректныйJSON
    case верхнийУровеньНеОбъект
    case некорректнаяИдентичностьКорня
    case чужойКорневойUUID
    case незавершённаяПоследняяЗапись
    case превышенПределБайт
    case превышенПределЗаписей
}

public enum СтатусСвязиКорняJSONL: String, Codable, Equatable, Sendable {
    case подтверждена
    case отсутствует
    case некорректна
}

public struct СобытиеЖурналаJSONL: Codable, Equatable, Sendable {
    public let номерСтроки: Int
    public let диапазонЗаписи: ДиапазонБайтJSONL
    public let диапазонТела: ДиапазонБайтJSONL
    public let sha256Тела: String
    public let sha256ЗаписиСLF: String
    public let порядок: Int?
    public let идентификатор: String?
    public let вид: String?
    public let время: String?
    public let корневойUUID: String?
    public let связьКорня: СтатусСвязиКорняJSONL
}

public struct ПовреждённыйДиапазонJSONL: Codable, Equatable, Sendable {
    public let номерСтроки: Int
    /// Полуоткрытый диапазон полной физической записи; LF входит, если он был.
    public let диапазон: ДиапазонБайтJSONL
    /// Полуоткрытый диапазон тела без завершающего LF.
    public let диапазонТела: ДиапазонБайтJSONL
    public let причины: [ПричинаПоврежденияЖурналаJSONL]
    public let телоЯвляетсяJSON: Bool?
    public let sha256Тела: String?
    public let sha256Записи: String?
    public let наблюдаемыйКорневойUUID: String?
}

public struct РезультатРазбораЖурналаJSONL: Codable, Equatable, Sendable {
    public let состояние: СостояниеЖурналаJSONL
    public let размерВхода: Int
    public let байтПросмотрено: Int
    public let записейПросмотрено: Int
    /// Покрытие означает, что каждый входной байт был осмотрен; оно не отменяет повреждений.
    public let полноеПокрытие: Bool
    public let события: [СобытиеЖурналаJSONL]
    public let повреждённыеДиапазоны: [ПовреждённыйДиапазонJSONL]
}

public enum ЧтениеЖурналаJSONL {
    private struct ОсмотрТела {
        let причины: [ПричинаПоврежденияЖурналаJSONL]
        let телоЯвляетсяJSON: Bool
        let порядок: Int?
        let идентификатор: String?
        let вид: String?
        let время: String?
        let корневойUUID: String?
        let связьКорня: СтатусСвязиКорняJSONL
    }

    private static let именаПоляКорня = ["корневойUUID", "корневаяЗадачаUUID", "rootTaskUUID", "rootUUID"]

    public static func разобрать(
        байты: Data,
        ожидаемыйКорневойUUID: String,
        максимумБайт: Int = 2_000_000,
        максимумЗаписей: Int = 4096
    ) -> РезультатРазбораЖурналаJSONL {
        var события: [СобытиеЖурналаJSONL] = []
        var повреждения: [ПовреждённыйДиапазонJSONL] = []
        let размер = байты.count

        guard размер > 0 else {
            повреждения.append(
                ПовреждённыйДиапазонJSONL(
                    номерСтроки: 1,
                    диапазон: ДиапазонБайтJSONL(начало: 0, конец: 0),
                    диапазонТела: ДиапазонБайтJSONL(начало: 0, конец: 0),
                    причины: [.пустойВход],
                    телоЯвляетсяJSON: false,
                    sha256Тела: вычислитьХеш(Data()),
                    sha256Записи: вычислитьХеш(Data()),
                    наблюдаемыйКорневойUUID: nil
                )
            )
            return РезультатРазбораЖурналаJSONL(
                состояние: .повреждён,
                размерВхода: 0,
                байтПросмотрено: 0,
                записейПросмотрено: 0,
                полноеПокрытие: true,
                события: [],
                повреждённыеДиапазоны: повреждения
            )
        }

        let пределБайт = min(размер, max(0, максимумБайт))
        let пределЗаписей = max(0, максимумЗаписей)
        let индексПредела = байты.index(байты.startIndex, offsetBy: пределБайт)
        var смещение = 0
        var номерСтроки = 1
        var числоЗаписей = 0
        var байтПросмотрено = 0
        var полноеПокрытие = true

        while смещение < пределБайт {
            guard числоЗаписей < пределЗаписей else {
                повреждения.append(
                    ПовреждённыйДиапазонJSONL(
                        номерСтроки: номерСтроки,
                        диапазон: ДиапазонБайтJSONL(начало: смещение, конец: размер),
                        диапазонТела: ДиапазонБайтJSONL(начало: смещение, конец: размер),
                        причины: [.превышенПределЗаписей],
                        телоЯвляетсяJSON: nil,
                        sha256Тела: nil,
                        sha256Записи: nil,
                        наблюдаемыйКорневойUUID: nil
                    )
                )
                полноеПокрытие = false
                байтПросмотрено = смещение
                break
            }

            let индексНачала = байты.index(байты.startIndex, offsetBy: смещение)
            if let индексLF = байты[индексНачала..<индексПредела].firstIndex(of: 0x0a) {
                let конецТела = байты.distance(from: байты.startIndex, to: индексLF)
                let индексКонцаЗаписи = байты.index(after: индексLF)
                let конецЗаписи = байты.distance(from: байты.startIndex, to: индексКонцаЗаписи)
                let диапазонТела = ДиапазонБайтJSONL(начало: смещение, конец: конецТела)
                let диапазонЗаписи = ДиапазонБайтJSONL(начало: смещение, конец: конецЗаписи)
                let тело = Data(байты[индексНачала..<индексLF])
                let запись = Data(байты[индексНачала..<индексКонцаЗаписи])
                let осмотр = осмотреть(тело, ожидаемыйКорневойUUID: ожидаемыйКорневойUUID)

                if осмотр.причины.isEmpty {
                    события.append(
                        СобытиеЖурналаJSONL(
                            номерСтроки: номерСтроки,
                            диапазонЗаписи: диапазонЗаписи,
                            диапазонТела: диапазонТела,
                            sha256Тела: вычислитьХеш(тело),
                            sha256ЗаписиСLF: вычислитьХеш(запись),
                            порядок: осмотр.порядок,
                            идентификатор: осмотр.идентификатор,
                            вид: осмотр.вид,
                            время: осмотр.время,
                            корневойUUID: осмотр.корневойUUID,
                            связьКорня: осмотр.связьКорня
                        )
                    )
                } else {
                    повреждения.append(
                        ПовреждённыйДиапазонJSONL(
                            номерСтроки: номерСтроки,
                            диапазон: диапазонЗаписи,
                            диапазонТела: диапазонТела,
                            причины: осмотр.причины,
                            телоЯвляетсяJSON: осмотр.телоЯвляетсяJSON,
                            sha256Тела: вычислитьХеш(тело),
                            sha256Записи: вычислитьХеш(запись),
                            наблюдаемыйКорневойUUID: осмотр.корневойUUID
                        )
                    )
                }

                смещение = конецЗаписи
                байтПросмотрено = смещение
                числоЗаписей += 1
                номерСтроки += 1
                continue
            }

            let диапазонТела = ДиапазонБайтJSONL(начало: смещение, конец: пределБайт)
            let тело = Data(байты[индексНачала..<индексПредела])
            числоЗаписей += 1

            if пределБайт < размер {
                повреждения.append(
                    ПовреждённыйДиапазонJSONL(
                        номерСтроки: номерСтроки,
                        диапазон: ДиапазонБайтJSONL(начало: смещение, конец: размер),
                        диапазонТела: ДиапазонБайтJSONL(начало: смещение, конец: размер),
                        причины: [.превышенПределБайт],
                        телоЯвляетсяJSON: nil,
                        sha256Тела: nil,
                        sha256Записи: nil,
                        наблюдаемыйКорневойUUID: nil
                    )
                )
                полноеПокрытие = false
                байтПросмотрено = пределБайт
            } else {
                let осмотр = осмотреть(тело, ожидаемыйКорневойUUID: ожидаемыйКорневойUUID)
                var причины = осмотр.причины
                причины.append(.незавершённаяПоследняяЗапись)
                повреждения.append(
                    ПовреждённыйДиапазонJSONL(
                        номерСтроки: номерСтроки,
                        диапазон: диапазонТела,
                        диапазонТела: диапазонТела,
                        причины: Array(Set(причины)).sorted { $0.rawValue < $1.rawValue },
                        телоЯвляетсяJSON: осмотр.телоЯвляетсяJSON,
                        sha256Тела: вычислитьХеш(тело),
                        sha256Записи: вычислитьХеш(тело),
                        наблюдаемыйКорневойUUID: осмотр.корневойUUID
                    )
                )
                байтПросмотрено = размер
            }
            break
        }

        if пределБайт < размер && полноеПокрытие {
            повреждения.append(
                ПовреждённыйДиапазонJSONL(
                    номерСтроки: номерСтроки,
                    диапазон: ДиапазонБайтJSONL(начало: пределБайт, конец: размер),
                    диапазонТела: ДиапазонБайтJSONL(начало: пределБайт, конец: размер),
                    причины: [.превышенПределБайт],
                    телоЯвляетсяJSON: nil,
                    sha256Тела: nil,
                    sha256Записи: nil,
                    наблюдаемыйКорневойUUID: nil
                )
            )
            полноеПокрытие = false
            байтПросмотрено = пределБайт
        }

        let состояние: СостояниеЖурналаJSONL = повреждения.isEmpty && полноеПокрытие
            ? .полный
            : .повреждён
        return РезультатРазбораЖурналаJSONL(
            состояние: состояние,
            размерВхода: размер,
            байтПросмотрено: байтПросмотрено,
            записейПросмотрено: числоЗаписей,
            полноеПокрытие: полноеПокрытие,
            события: события,
            повреждённыеДиапазоны: повреждения
        )
    }

    private static func осмотреть(_ тело: Data, ожидаемыйКорневойUUID: String) -> ОсмотрТела {
        var причины: [ПричинаПоврежденияЖурналаJSONL] = []
        guard !тело.isEmpty else {
            return ОсмотрТела(
                причины: [.пустаяЗапись],
                телоЯвляетсяJSON: false,
                порядок: nil,
                идентификатор: nil,
                вид: nil,
                время: nil,
                корневойUUID: nil,
                связьКорня: .отсутствует
            )
        }
        if тело.contains(0x0d) { причины.append(.запрещённыйCR) }
        if тело.contains(0x00) { причины.append(.нулевойБайт) }
        guard String(data: тело, encoding: .utf8) != nil else {
            причины.append(.некорректныйUTF8)
            return ОсмотрТела(
                причины: причины,
                телоЯвляетсяJSON: false,
                порядок: nil,
                идентификатор: nil,
                вид: nil,
                время: nil,
                корневойUUID: nil,
                связьКорня: .отсутствует
            )
        }
        guard let значение = try? JSONSerialization.jsonObject(with: тело, options: [.fragmentsAllowed]) else {
            причины.append(.некорректныйJSON)
            return ОсмотрТела(
                причины: причины,
                телоЯвляетсяJSON: false,
                порядок: nil,
                идентификатор: nil,
                вид: nil,
                время: nil,
                корневойUUID: nil,
                связьКорня: .отсутствует
            )
        }
        guard let объект = значение as? [String: Any] else {
            причины.append(.верхнийУровеньНеОбъект)
            return ОсмотрТела(
                причины: причины,
                телоЯвляетсяJSON: true,
                порядок: nil,
                идентификатор: nil,
                вид: nil,
                время: nil,
                корневойUUID: nil,
                связьКорня: .отсутствует
            )
        }

        let ключиКорня = именаПоляКорня.filter { объект.keys.contains($0) }
        let значенияКорня = ключиКорня.compactMap { объект[$0] as? String }
        var связьКорня: СтатусСвязиКорняJSONL = ключиКорня.isEmpty ? .отсутствует : .подтверждена
        if !ключиКорня.isEmpty && значенияКорня.count != ключиКорня.count {
            причины.append(.некорректнаяИдентичностьКорня)
            связьКорня = .некорректна
        }
        if !значенияКорня.isEmpty && !значенияКорня.allSatisfy({ $0 == ожидаемыйКорневойUUID }) {
            причины.append(.чужойКорневойUUID)
            связьКорня = .некорректна
        }

        return ОсмотрТела(
            причины: причины,
            телоЯвляетсяJSON: true,
            порядок: целоеЧисло(в: объект, ключи: ["порядок", "order"]),
            идентификатор: строка(в: объект, ключи: ["идентификатор", "eventID", "id"]),
            вид: строка(в: объект, ключи: ["вид", "тип", "type"]),
            время: строка(в: объект, ключи: ["время", "времяUTC", "timestamp"]),
            корневойUUID: значенияКорня.first,
            связьКорня: связьКорня
        )
    }

    private static func строка(в объект: [String: Any], ключи: [String]) -> String? {
        for ключ in ключи {
            if let значение = объект[ключ] as? String { return значение }
        }
        return nil
    }

    private static func целоеЧисло(в объект: [String: Any], ключи: [String]) -> Int? {
        for ключ in ключи {
            if let значение = объект[ключ] as? Int { return значение }
        }
        return nil
    }

    private static func вычислитьХеш(_ байты: Data) -> String {
        SHA256.hash(data: байты).map { String(format: "%02x", $0) }.joined()
    }
}

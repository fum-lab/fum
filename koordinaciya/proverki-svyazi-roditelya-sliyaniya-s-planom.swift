import Testing
@testable import KoordinaciyaMergeVerifier

struct ПроверкиСвязиРодителейСлияния {
    @Test("первый ожидаемый родитель совпадает с родителем плана")
    func совпадениеРодителяДопускается() {
        let основнойРодитель = String(repeating: "1", count: 40)
        let второйРодитель = String(repeating: "2", count: 40)

        let ошибки = ОценщикИдентичностиGit.проверитьСвязьПервогоРодителяСлиянияСПланом(
            ожидаемыеРодители: [основнойРодитель, второйРодитель],
            родительПлана: основнойРодитель
        )

        #expect(ошибки.isEmpty)
    }

    @Test("сырые ожидания не подменяют другого родителя плана")
    func несовпадениеРодителяОтклоняется() {
        let первыйОжидаемыйРодитель = String(repeating: "1", count: 40)
        let второйРодитель = String(repeating: "2", count: 40)
        let другойРодительПлана = String(repeating: "3", count: 40)

        let ошибки = ОценщикИдентичностиGit.проверитьСвязьПервогоРодителяСлиянияСПланом(
            ожидаемыеРодители: [первыйОжидаемыйРодитель, второйРодитель],
            родительПлана: другойРодительПлана
        )

        #expect(ошибки.contains("первый-ожидаемый-родитель-не-совпадает-с-планом"))
    }
}

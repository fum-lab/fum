import CryptoKit
import Foundation

// Чистая проекция принятого конечного поручения. Независимый допуск выбирает
// вызывающий владелец; хэши не удостоверяют его полномочия или live-состояние Git.
struct ИсточникСписка: Codable, Equatable, Sendable {
    var коммит: String
    var путь: String
    var хэш: String
}
struct КонтекстСписка: Codable, Equatable, Sendable {
    var дерево: String
    var реф: String
    var коммит: String
    var писатель: String
}
struct ОбязательствоСписка: Codable, Equatable, Sendable {
    var идентификатор: String
    var тип: String
    var критерий: String
    var действие: String?
    var зависимости: [String] = []
    var родитель: String? = nil
}
enum ВидСобытияСписка: String, Codable, Sendable {
    case наблюдение, уточнить, отменить, заменить, прогресс, подтвердить, коммит, отправить
    case принятьКорнем, принятьПоручение, остановить, намерение, исход
}
struct КомандаСписка: Codable, Equatable, Sendable {
    var идентификатор: String
    var вид: ВидСобытияСписка
    var текст: String
    var источник: ИсточникСписка
    var обязательство: String? = nil
    var добавки: [ОбязательствоСписка] = []
    var типРезультата: String? = nil
}
struct ОбластьСписка: Codable, Equatable, Sendable {
    var идентификатор: String
    var источник: ИсточникСписка
    var оригиналыЧеловека: [String]
    var дочерняяПостановка: String
    var обязательства: [ОбязательствоСписка]
    var команды: [КомандаСписка]
    var бюджет: Int
    var пределЗаписей: Int
    var полныйОхватПоручения: Bool
}
struct ДопускСписка: Codable, Sendable {
    var область: ОбластьСписка
    var контекст: КонтекстСписка
    var писатели: [String]
}
struct СобытиеСписка: Codable, Equatable, Sendable {
    var идентификатор: String
    var вид: ВидСобытияСписка
    var обязательство: String? = nil
    var команда: String? = nil
    var попытка: String? = nil
    var входНамерения: String? = nil
    var свидетельство: String = ""
}
enum СтатусПозицииСписка: String, Codable, Sendable { case ожидает, принято, отменено, заменено }
struct ПозицияСписка: Codable, Equatable, Sendable {
    var описание: ОбязательствоСписка
    var статус: СтатусПозицииСписка = .ожидает
    var замена: String? = nil
    var свидетельства: [String] = []
}
enum ВидРешенияСписка: String, Codable, Sendable {
    case продолжить, ждатьРодителя, завершитьПоручение, остановлено, неизвестно
}
struct РешениеСписка: Codable, Equatable, Sendable {
    var вид: ВидРешенияСписка
    var обязательство: String? = nil
    var препятствия: [String] = []
    // Даже закрытый локальный assignment не удостоверяет завершения ROOT.
    var закрываетROOT = false
}
struct ПопыткаСписка: Codable, Equatable, Sendable {
    var идентификатор: String
    var поколение: Int
    var отпечаток: String
    var событие: String
    var вход: String
    var до: String
    var решение: РешениеСписка
    var исходЗаписан = false
}
struct СнимокСписка: Codable, Equatable, Sendable {
    var идентификатор: String
    var область: String
    var позиции: [ПозицияСписка]
    var поколение = 0
    var команды: [String] = []
    var счётчики: [String: Int] = [:]
    var попытки: [ПопыткаСписка] = []
    var остановлен = false
    var поручениеПринято = false
}
struct ЗаписьПереходаСписка: Codable, Equatable, Sendable {
    var номер: Int
    var предыдущая: String
    var до: String
    var после: String
    var версияКода: String
    var писатель: String
    var событие: СобытиеСписка
    var вход: String
    var команда: String?
    var решение: РешениеСписка?
    var выход: String
}
struct СостояниеСписка: Codable, Equatable, Sendable {
    var снимок: СнимокСписка
    var цепочка: [ЗаписьПереходаСписка] = []
}
struct РезультатПереходаСписка: Codable, Sendable {
    var состояние: СостояниеСписка
    var решение: РешениеСписка?
    var повтор = false
}
enum ОшибкаСписка: Error, Equatable { case отказ(String) }

enum СписокРабот {
    static let версия = "fum.координация.переход-списка-работ.1"
    static func хэш<T: Encodable>(_ значение: T) throws -> String {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return SHA256.hash(data: try кодировщик.encode(значение)).map { String(format: "%02x", $0) }.joined()
    }
    private static func требовать(_ условие: Bool, _ причина: String) throws {
        if !условие { throw ОшибкаСписка.отказ(причина) }
    }
    static func начать(допуск: ДопускСписка) throws -> СостояниеСписка {
        let область = допуск.область
        try требовать(!область.идентификатор.isEmpty && !область.дочерняяПостановка.isEmpty &&
            область.бюджет > 0 && область.пределЗаписей > 0, "неполная-область")
        for источник in [область.источник] + область.команды.map(\.источник) {
            try требовать(источник.коммит.count == 40 && источник.хэш.count == 64 &&
                (источник.коммит + источник.хэш).allSatisfy { "0123456789abcdef".contains($0) } &&
                !источник.путь.isEmpty && !источник.путь.hasPrefix("/") &&
                !источник.путь.split(separator: "/").contains(".."), "неполный-источник")
        }
        try требовать(Set(область.команды.map(\.идентификатор)).count == область.команды.count &&
            область.команды.allSatisfy { !$0.идентификатор.isEmpty && !$0.текст.isEmpty }, "повтор-команды")
        var исходнаяОбласть = область
        исходнаяОбласть.команды = [] // Поздние принятые команды не заменяют genesis.
        var снимок = СнимокСписка(идентификатор: область.идентификатор, область: try хэш(исходнаяОбласть),
                                  позиции: область.обязательства.map { ПозицияСписка(описание: $0) })
        try проверитьГраф(снимок)
        // Начало не объявляет пустой или частичный источник полным.
        снимок.поручениеПринято = false
        return СостояниеСписка(снимок: снимок)
    }
    static func переход(_ состояние: СостояниеСписка, _ событие: СобытиеСписка,
                        допуск: ДопускСписка, контекст: КонтекстСписка) throws -> РезультатПереходаСписка {
        try требовать(контекст == допуск.контекст && допуск.писатели.contains(контекст.писатель) &&
            UUID(uuidString: контекст.писатель) != nil && контекст.дерево.hasPrefix("/") &&
            контекст.реф.hasPrefix("refs/heads/") && контекст.коммит.count == 40, "не-сходится-W-ref-HEAD-native")
        var восстановленное = try начать(допуск: допуск).снимок
        var предыдущая = восстановленное.область
        var идентификаторы = Set<String>()
        for (номер, запись) in состояние.цепочка.enumerated() {
            try требовать(номер < допуск.область.пределЗаписей ||
                (номер == допуск.область.пределЗаписей && запись.событие.вид == .остановить && !восстановленное.остановлен),
                "цепь-за-пределом-допуска")
            try требовать(запись.номер == номер && запись.предыдущая == предыдущая && запись.версияКода == версия &&
                допуск.писатели.contains(запись.писатель) && идентификаторы.insert(запись.событие.идентификатор).inserted &&
                запись.команда == (try подтверждениеКоманды(запись.событие, допуск.область)) &&
                запись.вход == (try хэш(запись.событие)) && запись.до == (try хэш(восстановленное)), "разрыв-цепи")
            let переход = try применить(восстановленное, запись.событие, допуск.область)
            try требовать(запись.после == (try хэш(переход.0)) && запись.решение == переход.1 &&
                запись.выход == (try хэш(переход.1)), "неверный-outcome")
            восстановленное = переход.0
            предыдущая = try хэш(запись)
        }
        try требовать(восстановленное == состояние.снимок, "потеря-или-подмена-проекции")
        if let прежняя = состояние.цепочка.first(where: { $0.событие.идентификатор == событие.идентификатор }) {
            try требовать(прежняя.событие == событие && прежняя.вход == (try хэш(событие)), "reentry-с-другим-input")
            let завершённая = событие.вид == .намерение ? состояние.снимок.попытки.first(where: {
                $0.идентификатор == событие.попытка && $0.исходЗаписан
            })?.решение : nil
            return РезультатПереходаСписка(состояние: состояние,
                решение: состояние.снимок.остановлен ? РешениеСписка(вид: .остановлено) : завершённая ?? прежняя.решение, повтор: true)
        }
        if событие.вид == .намерение, let прежняя = состояние.снимок.попытки.first(where: {
            $0.идентификатор == событие.попытка
        }) {
            var повтор = событие; повтор.идентификатор = прежняя.событие
            try требовать(прежняя.вход == (try хэш(повтор)), "attempt-с-другим-input")
            let выбор = состояние.снимок.остановлен ? РешениеСписка(вид: .остановлено) :
                прежняя.исходЗаписан ? прежняя.решение : РешениеСписка(вид: .неизвестно, препятствия: ["intent-без-outcome"])
            return РезультатПереходаСписка(состояние: состояние, решение: выбор, повтор: true)
        }
        if событие.вид == .исход, let прежняя = состояние.снимок.попытки.first(where: {
            $0.идентификатор == событие.попытка && $0.исходЗаписан
        }) {
            guard let запись = состояние.цепочка.first(where: {
                $0.событие.вид == .исход && $0.событие.попытка == событие.попытка
            }) else { throw ОшибкаСписка.отказ("нет-первичного-outcome") }
            var повтор = событие; повтор.идентификатор = запись.событие.идентификатор
            try требовать(запись.вход == (try хэш(повтор)), "reentry-outcome-с-другим-input")
            let выбор = состояние.снимок.остановлен ? РешениеСписка(вид: .остановлено) : прежняя.решение
            return РезультатПереходаСписка(состояние: состояние, решение: выбор, повтор: true)
        }
        if состояние.снимок.остановлен {
            return РезультатПереходаСписка(состояние: состояние, решение: РешениеСписка(вид: .остановлено), повтор: true)
        }
        let остановка = try событие.вид == .остановить && подтверждениеКоманды(событие, допуск.область) != nil
        try требовать(!событие.идентификатор.isEmpty && (остановка || состояние.цепочка.count < допуск.область.пределЗаписей),
                      "пустой-ID-или-предел-цепи")
        let (снимок, решение) = try применить(состояние.снимок, событие, допуск.область)
        var новое = состояние
        новое.снимок = снимок
        новое.цепочка.append(ЗаписьПереходаСписка(номер: состояние.цепочка.count, предыдущая: предыдущая,
            до: try хэш(состояние.снимок), после: try хэш(снимок), версияКода: версия, писатель: контекст.писатель,
            событие: событие, вход: try хэш(событие), команда: try подтверждениеКоманды(событие, допуск.область),
            решение: решение, выход: try хэш(решение)))
        return РезультатПереходаСписка(состояние: новое, решение: решение)
    }
    private static func подтверждениеКоманды(_ событие: СобытиеСписка, _ область: ОбластьСписка) throws -> String? {
        try область.команды.first(where: { $0.идентификатор == событие.команда && $0.вид == событие.вид }).map(хэш)
    }
    private static func проверитьГраф(_ снимок: СнимокСписка) throws {
        let позиции = снимок.позиции
        let имена = Set(позиции.map(\.описание.идентификатор))
        try требовать(имена.count == позиции.count && позиции.allSatisfy {
            !$0.описание.идентификатор.isEmpty && !$0.описание.тип.isEmpty && !$0.описание.критерий.isEmpty &&
            Set($0.описание.зависимости).count == $0.описание.зависимости.count &&
            $0.описание.зависимости.allSatisfy(имена.contains)
        }, "неверные-ID-или-зависимости")
        let связи = Dictionary(uniqueKeysWithValues: позиции.map { ($0.описание.идентификатор,
            $0.описание.зависимости + ($0.замена.map { [$0] } ?? [])) })
        var готовы = Set<String>(); var открыты = Set<String>()
        func обойти(_ имя: String) throws {
            if готовы.contains(имя) { return }
            try требовать(имена.contains(имя) && открыты.insert(имя).inserted, "цикл-зависимостей-или-замен")
            for следующее in связи[имя] ?? [] { try обойти(следующее) }
            открыты.remove(имя); готовы.insert(имя)
        }
        for имя in имена { try обойти(имя) }
    }
    private static func отпечаток(_ снимок: СнимокСписка) throws -> String {
        // Доставка, actor, статусный ответ и attempt не меняют смысл todo.
        try хэш(снимок.позиции.map { ПозицияСписка(описание: $0.описание, статус: $0.статус, замена: $0.замена) })
    }
    private static func решение(_ снимок: СнимокСписка, _ область: ОбластьСписка) throws -> РешениеСписка {
        if снимок.остановлен { return РешениеСписка(вид: .остановлено) }
        if снимок.попытки.contains(where: { !$0.исходЗаписан }) {
            return РешениеСписка(вид: .неизвестно, препятствия: ["intent-без-outcome"])
        }
        let ключ = "\(снимок.поколение):\(try отпечаток(снимок))"
        if снимок.счётчики[ключ, default: 0] >= область.бюджет {
            return РешениеСписка(вид: .ждатьРодителя, препятствия: ["исчерпан-бюджет:\(ключ)"])
        }
        let поИмени = Dictionary(uniqueKeysWithValues: снимок.позиции.map { ($0.описание.идентификатор, $0) })
        func принято(_ имя: String) -> Bool {
            guard let позиция = поИмени[имя] else { return false }
            if позиция.статус == .заменено, let замена = позиция.замена { return принято(замена) }
            return позиция.статус == .принято
        }
        var препятствия: [String] = []
        for позиция in снимок.позиции where позиция.статус == .ожидает {
            let описание = позиция.описание
            let зависимости = описание.зависимости.filter { !принято($0) }
            if зависимости.isEmpty, let действие = описание.действие, !действие.isEmpty {
                return РешениеСписка(вид: .продолжить, обязательство: описание.идентификатор)
            }
            препятствия += зависимости.map { "\(описание.идентификатор):зависимость:\($0)" }
            if описание.действие?.isEmpty != false { препятствия.append("\(описание.идентификатор):нет-разрешённого-действия") }
        }
        if !препятствия.isEmpty { return РешениеСписка(вид: .ждатьРодителя, препятствия: препятствия) }
        if область.полныйОхватПоручения && снимок.поручениеПринято {
            return РешениеСписка(вид: .завершитьПоручение)
        }
        return РешениеСписка(вид: .ждатьРодителя, препятствия: [область.полныйОхватПоручения
            ? "нет-приёмки-конечного-поручения" : "частичный-охват-поручения"])
    }
    private static func применить(_ прежний: СнимокСписка, _ событие: СобытиеСписка,
                                   _ область: ОбластьСписка) throws -> (СнимокСписка, РешениеСписка?) {
        var снимок = прежний
        if событие.вид == .намерение {
            let выбор = try решение(снимок, область)
            if выбор.вид == .неизвестно || выбор.вид == .остановлено { return (снимок, выбор) }
            guard let имя = событие.попытка, !имя.isEmpty else { throw ОшибкаСписка.отказ("нет-attempt-ID") }
            try требовать(!снимок.попытки.contains { $0.идентификатор == имя }, "attempt-уже-использован")
            снимок.попытки.append(ПопыткаСписка(идентификатор: имя, поколение: снимок.поколение,
                отпечаток: try отпечаток(снимок), событие: событие.идентификатор,
                вход: try хэш(событие), до: try хэш(снимок), решение: выбор))
            return (снимок, РешениеСписка(вид: .неизвестно, препятствия: ["ожидается-outcome:\(имя)"]))
        }
        if событие.вид == .исход {
            guard let номер = снимок.попытки.firstIndex(where: { $0.идентификатор == событие.попытка }) else {
                throw ОшибкаСписка.отказ("outcome-без-intent")
            }
            let попытка = снимок.попытки[номер]
            try требовать(попытка.вход == событие.входНамерения && попытка.поколение == снимок.поколение &&
                попытка.отпечаток == (try отпечаток(снимок)), "outcome-не-связан-с-intent")
            let выбор = снимок.остановлен ? РешениеСписка(вид: .остановлено) : попытка.решение
            if !попытка.исходЗаписан {
                снимок.попытки[номер].исходЗаписан = true
                if выбор.вид == .продолжить {
                    let ключ = "\(попытка.поколение):\(попытка.отпечаток)"
                    снимок.счётчики[ключ, default: 0] += 1
                }
            }
            return (снимок, выбор)
        }
        if событие.вид == .наблюдение { return (снимок, nil) }
        if [.подтвердить, .прогресс, .коммит, .отправить].contains(событие.вид) {
            guard let номер = снимок.позиции.firstIndex(where: { $0.описание.идентификатор == событие.обязательство }) else {
                throw ОшибкаСписка.отказ("неизвестный-ID-прогресса")
            }
            снимок.позиции[номер].свидетельства.append("\(событие.вид.rawValue):\(событие.свидетельство)")
            return (снимок, nil)
        }
        guard let команда = область.команды.first(where: { $0.идентификатор == событие.команда && $0.вид == событие.вид }) else {
            throw ОшибкаСписка.отказ("нет-независимо-принятой-команды")
        }
        if событие.вид == .остановить { снимок.остановлен = true; return (снимок, РешениеСписка(вид: .остановлено)) }
        try требовать(!снимок.остановлен && !снимок.попытки.contains { !$0.исходЗаписан }, "STOP-или-неизвестный-исход")
        if снимок.команды.contains(команда.идентификатор) { return (снимок, nil) }
        if событие.вид == .принятьПоручение {
            try требовать(область.полныйОхватПоручения && снимок.позиции.allSatisfy { $0.статус != .ожидает }, "неполная-приёмка")
            снимок.поручениеПринято = true
        } else if событие.вид == .уточнить {
            for добавка in команда.добавки { снимок.позиции.append(ПозицияСписка(описание: добавка)) }
            if !команда.добавки.isEmpty { снимок.поколение += 1; снимок.поручениеПринято = false }
        } else {
            guard let номер = снимок.позиции.firstIndex(where: { $0.описание.идентификатор == команда.обязательство }) else {
                throw ОшибкаСписка.отказ("неизвестное-обязательство-команды")
            }
            try требовать(снимок.позиции[номер].статус == .ожидает, "обязательство-уже-закрыто")
            if событие.вид == .принятьКорнем {
                try требовать(команда.типРезультата == снимок.позиции[номер].описание.тип, "неверный-тип-принятого-результата")
                снимок.позиции[номер].статус = .принято
            } else if событие.вид == .отменить { снимок.позиции[номер].статус = .отменено }
            else if событие.вид == .заменить {
                try требовать(команда.добавки.count == 1, "нет-точной-замены")
                снимок.позиции[номер].статус = .заменено
                снимок.позиции[номер].замена = команда.добавки[0].идентификатор
                снимок.позиции.append(ПозицияСписка(описание: команда.добавки[0]))
            } else { throw ОшибкаСписка.отказ("неверный-переход-команды") }
            снимок.поколение += 1; снимок.поручениеПринято = false
        }
        снимок.команды.append(команда.идентификатор)
        try проверитьГраф(снимок)
        return (снимок, nil)
    }
}


enum ОшибкаПотребителяСписка: Error, Equatable { case отказ(String) }

private func требоватьСписок(_ условие: Bool, _ причина: String) throws {
    if !условие { throw ОшибкаПотребителяСписка.отказ(причина) }
}
private func байтыСписка<T: Encodable>(_ значение: T) throws -> Data {
    let кодировщик = JSONEncoder(); кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
    return try кодировщик.encode(значение)
}
private func хэшИсходника(_ данные: Data) -> String {
    SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}
private struct СохранённыйШагСписка: Codable {

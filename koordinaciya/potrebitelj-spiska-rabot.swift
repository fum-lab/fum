import CryptoKit
import Foundation
import Darwin
import КонтейнерНаблюдений

enum РежимПрограммыСписка: String, Codable, Sendable { case создать, применить, прочитать }

/// Один шаг программы перехода, пригодный как JSON-выход оператора FUMA.
/// Здесь нет выбора ROOT-задач, внешних argv или запуска выбранного действия.
struct ПрограммаПотребителяСписка: Codable, Sendable {
    var схема = "fum.координация.программа-потребителя-списка.1"
    var режим: РежимПрограммыСписка
    var корневойUUID: String
    var допуск: ДопускСписка
    var наблюдение: КонтекстСписка
    var хэшОбласти: String
    var пределСобытий = 32
    var исходныеБайты: Data? = nil
    var предыдущаяКвитанция: Квитанция? = nil
    var событие: СобытиеСписка? = nil
}

struct ОтветПотребителяСписка: Codable, Sendable {
    let схема: String
    let квитанция: Квитанция
    let состояние: СостояниеСписка
    let первичнаяОбласть: ОбластьСписка
    let исходныеБайты: Data
    let решение: РешениеСписка?
    let повтор: Bool
    let толькоЧтение: Bool
}

enum ОшибкаПотребителяСписка: Error, Equatable { case отказ(String) }

private func требоватьСписок(_ условие: Bool, _ причина: String) throws {
    if !условие { throw ОшибкаПотребителяСписка.отказ(причина) }
}
private func байтыСписка<T: Encodable>(_ значение: T) throws -> Data {
    let кодировщик = JSONEncoder(); кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
    return try кодировщик.encode(значение)
}
private func хэшИсходника(_ данные: Data) -> String {
    SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}
private struct СохранённыйШагСписка: Codable {
    var версия = "fum.координация.checkpoint-списка.1"
    var ядро = СписокРабот.версия
    let программа: ПрограммаПотребителяСписка
    let состояние: СостояниеСписка
    let решение: РешениеСписка?
}

/// Единственный синхронный владелец существующего Сегмента. Между редукцией,
/// append+fsync и публикацией нет await. Наблюдаемый commit после ошибки fsync
/// требует exact re-sync; одно RO-чтение не доказывает физическую durability.
actor ХранилищеСпискаРабот {
    private let сегмент: Сегмент
    private let запись: Bool
    private let первичная: ПрограммаПотребителяСписка
    private var шаги: [СохранённыйШагСписка]
    private var квитанции: [Квитанция]
    private var отказ = false
    private static let пределДанных = 16 * 1_048_576
    private static let резерв = 3 * 1_048_576

    static func хэшОбласти(_ область: ОбластьСписка) throws -> String {
        var исходная = область; исходная.команды = []
        return try СписокРабот.хэш(исходная)
    }
    init(корень: URL, программа: ПрограммаПотребителяСписка, запись: Bool,
         создать: Bool = false, операции: ФайловыеОперации = .системные) throws {
        try Self.проверить(программа)
        try требоватьСписок(корень.isFileURL && корень.path == корень.resolvingSymlinksInPath().standardizedFileURL.path &&
            корень.path != программа.наблюдение.дерево &&
            !корень.path.hasPrefix(программа.наблюдение.дерево + "/"), "небезопасный-корень-данных")
        var сведения = stat()
        try требоватьСписок(lstat(корень.path, &сведения) == 0 && (сведения.st_mode & S_IFMT) == S_IFDIR &&
            сведения.st_uid == getuid() && (сведения.st_mode & 0o777) == 0o700, "нужен-собственный-каталог-0700")
        try требоватьСписок(!создать || (запись && программа.режим == .создать), "нет-явного-создания")
        let файл = корень.appendingPathComponent("сегмент.fumobs")
        if FileManager.default.fileExists(atPath: файл.path) {
            let размер = try файл.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? Self.пределДанных + 1
            try требоватьСписок(размер <= Self.пределДанных, "предел-данных")
        }
        let открытый = try Сегмент(кореньДанных: корень, запись: запись, создать: создать, операции: операции)
        do {
            try требоватьСписок(!открытый.естьХвост, "неполный-checkpoint-нужна-отдельная-процедура")
            var восстановленные: [СохранённыйШагСписка] = []
            var квитанции = открытый.записи
            try требоватьСписок(квитанции.count <= программа.пределСобытий + 1, "предел-checkpoint")
            for (номер, квитанция) in квитанции.enumerated() {
                try требоватьСписок(квитанция.размер <= 2 * 1_048_576, "предел-записи")
                let данные = try открытый.извлечь(квитанция.описание.идентификатор)
                let шаг = try JSONDecoder().decode(СохранённыйШагСписка.self, from: данные)
                try Self.проверить(шаг.программа)
                try Self.связать(шаг.программа, программа)
                try требоватьСписок(шаг.версия == "fum.координация.checkpoint-списка.1" && шаг.ядро == СписокРабот.версия &&
                    данные == байтыСписка(шаг) && квитанция.описание == Self.описание(шаг, номер), "подмена-checkpoint")
                if номер == 0 {
                    try требоватьСписок(шаг.программа.режим == .создать && шаг.решение == nil &&
                        шаг.состояние == СписокРабот.начать(допуск: шаг.программа.допуск), "неверный-genesis")
                } else {
                    let предыдущий = восстановленные[номер - 1]
                    try Self.связать(шаг.программа, восстановленные[0].программа)
                    try требоватьСписок(шаг.программа.режим == .применить &&
                        шаг.программа.предыдущаяКвитанция == квитанции[номер - 1], "разрыв-квитанций")
                    let результат = try Self.вычислить(шаг.программа, предыдущий.состояние)
                    try требоватьСписок(!результат.повтор && результат.состояние == шаг.состояние &&
                        результат.решение == шаг.решение, "подмена-проекции")
                }
                восстановленные.append(шаг)
            }
            if восстановленные.isEmpty {
                try требоватьСписок(создать && программа.режим == .создать, "нет-checkpoint-не-begin")
                let начало = СохранённыйШагСписка(программа: программа,
                    состояние: try СписокРабот.начать(допуск: программа.допуск), решение: nil)
                let данные = try байтыСписка(начало)
                try требоватьСписок(данные.count <= 2 * 1_048_576, "предел-genesis")
                квитанции = [try открытый.добавить(Self.описание(начало, 0), данные: данные)]
                восстановленные = [начало]
            }
            self.сегмент = открытый; self.запись = запись
            self.первичная = восстановленные[0].программа
            self.шаги = восстановленные; self.квитанции = квитанции
        } catch { открытый.закрыть(); throw error }
    }
    func принять(_ программа: ПрограммаПотребителяСписка) throws -> ОтветПотребителяСписка {
        try доступ(); try требоватьСписок(запись, "только-чтение")
        try Self.проверить(программа); try Self.связать(программа, первичная)
        try требоватьСписок(программа.режим == .применить, "нужен-переход")
        let событие = try событиеПрограммы(программа)
        // Сначала exact duplicate, затем CAS: потерянный ответ не создаёт новый ID.
        if let номер = шаги.firstIndex(where: { $0.программа.событие?.идентификатор == событие.идентификатор }) {
            try требоватьСписок(байтыСписка(шаги[номер].программа) == байтыСписка(программа), "ID-с-другим-payload")
            do { _ = try сегмент.добавить(квитанции[номер].описание, данные: байтыСписка(шаги[номер])) }
            catch { отказ = true; throw error }
            return ответ(решение: безопасноеРешение(), повтор: true)
        }
        try требоватьСписок(программа.предыдущаяКвитанция == квитанции.last, "stale-или-нет-CAS")
        let старое = шаги[шаги.count - 1].состояние
        if событие.вид == .намерение && старое.снимок.попытки.contains(where: { !$0.исходЗаписан }) {
            return ответ(решение: безопасноеРешение(), повтор: true)
        }
        let результат = try Self.вычислить(программа, старое)
        if результат.повтор { return ответ(решение: безопасноеРешение(), повтор: true) }
        let остановка = событие.вид == .остановить
        let число = шаги.count - 1
        try требоватьСписок(число < первичная.пределСобытий - (остановка ? 0 : 1), "предел-с-резервом-STOP")
        let размер = try байтыСписка(результат.состояние).count
        try требоватьСписок(размер <= 1_048_576 - (остановка ? 0 : 131_072), "предел-проекции-с-резервом-STOP")
        let шаг = СохранённыйШагСписка(программа: программа, состояние: результат.состояние, решение: результат.решение)
        let данные = try байтыСписка(шаг)
        // Верхняя оценка framing, заголовка и commit; резерв для STOP конечен.
        let занято = квитанции.reduce(0) { $0 + Int($1.размер) + 131_072 }
        try требоватьСписок(данные.count <= 2 * 1_048_576 &&
            занято + данные.count + 131_072 <= Self.пределДанных - (остановка ? 0 : Self.резерв), "предел-данных-с-резервом-STOP")
        let квитанция: Квитанция
        do { квитанция = try сегмент.добавить(Self.описание(шаг, шаги.count), данные: данные) }
        catch { отказ = true; throw error }
        шаги.append(шаг); квитанции.append(квитанция)
        return ответ(решение: результат.решение, повтор: false)
    }
    func прочитать() throws -> ОтветПотребителяСписка {
        try доступ(); return ответ(решение: безопасноеРешение(), повтор: false)
    }
    func закрыть() { сегмент.закрыть(); отказ = true }
    private func доступ() throws { try требоватьСписок(!отказ, "UNKNOWN-нужно-close-reopen") }
    private func безопасноеРешение() -> РешениеСписка? {
        let снимок = шаги[шаги.count - 1].состояние.снимок
        if снимок.остановлен { return РешениеСписка(вид: .остановлено) }
        if снимок.попытки.contains(where: { !$0.исходЗаписан }) {
            return РешениеСписка(вид: .неизвестно, препятствия: ["durable-intent-без-outcome"])
        }
        return nil // RO restart не выдаёт прежнее разрешение эффекта заново.
    }
    private func ответ(решение: РешениеСписка?, повтор: Bool) -> ОтветПотребителяСписка {
        ОтветПотребителяСписка(схема: "fum.координация.ответ-потребителя-списка.1", квитанция: квитанции[квитанции.count - 1],
            состояние: шаги[шаги.count - 1].состояние, первичнаяОбласть: первичная.допуск.область,
            исходныеБайты: первичная.исходныеБайты!, решение: решение, повтор: повтор, толькоЧтение: !запись)
    }
    private func событиеПрограммы(_ программа: ПрограммаПотребителяСписка) throws -> СобытиеСписка {
        guard let событие = программа.событие else { throw ОшибкаПотребителяСписка.отказ("нет-события") }
        return событие
    }
    private static func вычислить(_ программа: ПрограммаПотребителяСписка, _ состояние: СостояниеСписка) throws -> РезультатПереходаСписка {
        guard let событие = программа.событие else { throw ОшибкаПотребителяСписка.отказ("нет-события") }
        return try СписокРабот.переход(состояние, событие, допуск: программа.допуск, контекст: программа.наблюдение)
    }
    private static func связать(_ программа: ПрограммаПотребителяСписка, _ якорь: ПрограммаПотребителяСписка) throws {
        try требоватьСписок(программа.корневойUUID == якорь.корневойUUID && программа.хэшОбласти == якорь.хэшОбласти &&
            программа.пределСобытий == якорь.пределСобытий && программа.допуск.контекст == якорь.допуск.контекст &&
            программа.допуск.писатели == якорь.допуск.писатели, "другой-якорь-допуска")
    }
    private static func проверить(_ программа: ПрограммаПотребителяСписка) throws {
        try требоватьСписок(программа.схема == "fum.координация.программа-потребителя-списка.1" &&
            программа.пределСобытий > 0 && программа.пределСобытий <= 32 &&
            UUID(uuidString: программа.корневойUUID) != nil &&
            программа.наблюдение == программа.допуск.контекст &&
            программа.допуск.писатели == [программа.наблюдение.писатель] &&
            UUID(uuidString: программа.наблюдение.писатель) != nil &&
            программа.наблюдение.писатель != программа.корневойUUID &&
            программа.наблюдение.дерево.hasPrefix("/") && программа.наблюдение.реф.hasPrefix("refs/heads/") &&
            программа.наблюдение.коммит.count == 40 && программа.наблюдение.коммит.allSatisfy({ "0123456789abcdef".contains($0) }) &&
            программа.хэшОбласти == хэшОбласти(программа.допуск.область) &&
            байтыСписка(программа).count <= 65_536, "неполная-программа-допуск")
        _ = try СписокРабот.начать(допуск: программа.допуск)
        if программа.режим == .создать {
            try требоватьСписок(программа.событие == nil && программа.предыдущаяКвитанция == nil &&
                программа.исходныеБайты.map(хэшИсходника) == программа.допуск.область.источник.хэш, "нет-точных-исходных-байтов")
        } else {
            try требоватьСписок(программа.исходныеБайты == nil &&
                (программа.режим == .применить ? программа.событие != nil :
                    программа.событие == nil && программа.предыдущаяКвитанция == nil), "неверный-режим-входа")
        }
    }
    private static func описание(_ шаг: СохранённыйШагСписка, _ номер: Int) throws -> ОписаниеНаблюдения {
        ОписаниеНаблюдения(идентификатор: try СписокРабот.хэш(шаг.программа), тип: "fum.worklist.checkpoint.1",
            источник: шаг.программа.хэшОбласти, время: "checkpoint-\(номер)",
            спецификация: Data(СписокРабот.версия.utf8))
    }
}

public enum КомандаПотребителяСписка {
    /// stdin — одна конечная программа FUMA; argv — только приватный каталог.
    /// Это потребитель перехода, без выполнения действия и без live Stop hook.
    public static func выполнить() async -> Int32 {
        do {
            try требоватьСписок(CommandLine.arguments.count == 2, "нужен-каталог-данных")
            var вход = Data()
            while вход.count <= 65_536 {
                let часть = try FileHandle.standardInput.read(upToCount: 65_537 - вход.count) ?? Data()
                if часть.isEmpty { break }; вход.append(часть)
            }
            try требоватьСписок(вход.count <= 65_536, "предел-входа")
            let программа = try JSONDecoder().decode(ПрограммаПотребителяСписка.self, from: вход)
            try требоватьСписок(ProcessInfo.processInfo.environment["CODEX_THREAD_ID"] == программа.наблюдение.писатель &&
                URL(fileURLWithPath: FileManager.default.currentDirectoryPath).resolvingSymlinksInPath().path == программа.наблюдение.дерево,
                "не-сходится-native-W")
            for (аргументы, ожидается) in [(["rev-parse", "HEAD"], программа.наблюдение.коммит),
                (["symbolic-ref", "HEAD"], программа.наблюдение.реф),
                (["rev-parse", "--show-toplevel"], программа.наблюдение.дерево)] {
                let процесс = Process(); процесс.executableURL = URL(fileURLWithPath: "/usr/bin/git")
                процесс.arguments = ["--no-replace-objects"] + аргументы
                процесс.currentDirectoryURL = URL(fileURLWithPath: программа.наблюдение.дерево)
                // Ни GIT_DIR, ни GIT_CONFIG_*, ни alternate object store вызывающего
                // процесса не могут подменить физический checkout этого guard.
                var среда = ProcessInfo.processInfo.environment.filter { !$0.key.hasPrefix("GIT_") }
                среда["GIT_OPTIONAL_LOCKS"] = "0"; среда["GIT_CONFIG_NOSYSTEM"] = "1"
                среда["GIT_CONFIG_GLOBAL"] = "/dev/null"; процесс.environment = среда
                let вывод = Pipe(); процесс.standardOutput = вывод; процесс.standardError = FileHandle.nullDevice
                try процесс.run(); let данные = вывод.fileHandleForReading.readDataToEndOfFile(); процесс.waitUntilExit()
                try требоватьСписок(процесс.terminationStatus == 0 && String(decoding: данные, as: UTF8.self)
                    .trimmingCharacters(in: .whitespacesAndNewlines) == ожидается, "не-сходится-live-Git")
            }
            let хранилище = try ХранилищеСпискаРабот(корень: URL(fileURLWithPath: CommandLine.arguments[1]), программа: программа,
                запись: программа.режим != .прочитать, создать: программа.режим == .создать)
            let ответ: ОтветПотребителяСписка
            do {
                if программа.режим == .применить { ответ = try await хранилище.принять(программа) }
                else { ответ = try await хранилище.прочитать() }
            }
            catch { await хранилище.закрыть(); throw error }
            await хранилище.закрыть()
            try FileHandle.standardOutput.write(contentsOf: байтыСписка(ответ) + Data([10])); return 0
        } catch {
            try? FileHandle.standardError.write(contentsOf: Data("UNKNOWN/отказ: \(error)\n".utf8)); return 1
        }
    }
}

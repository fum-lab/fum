    let состояние: СостояниеСписка
    let решение: РешениеСписка?
}


/// V2 хранит одну дельту. V1 читается неизменно; его вложенные trace-prefix
/// проверяются по кэшированным хэшам. Семантический replay ядра — один на open.
struct ДельтаСписка: Codable {
    var версия = "fum.координация.delta-списка.2"
    let программа: ПрограммаПотребителяСписка
    let эпохаДо: String
    let снимок: СнимокСписка
    let переход: ЗаписьПереходаСписка?
    let решение: РешениеСписка?
    let эпохаПосле: ЭпохаСписка
    let поручение: ПоручениеПереносаЭпохи?
}
private struct ЗапомненнаяЗаписьСписка {
    let программа: ПрограммаПотребителяСписка
    let данные: Data
    let квитанция: Квитанция
    let поручение: ПоручениеПереносаЭпохи?
}
private struct ЯкорьСостоянияСписка: Encodable {
    let версия = "fum.координация.якорь-состояния.1"
    let снимок: String
    let хвост: String
    let переходов: Int
}
actor ХранилищеСпискаРабот {
    private let сегмент: Сегмент
    private let запись: Bool
    private let первичная: ПрограммаПотребителяСписка
    private var состояние: СостояниеСписка
    private var эпоха: ЭпохаСписка
    private var область: ОбластьСписка
    private var писатели: Set<String>
    private var записи: [ЗапомненнаяЗаписьСписка]
    private var сторона: ДовереннаяСторонаЭпохи?
    private var обход: СчётчикиВосстановленияСписка
    private var отказ = false
    private static let пределДанных = 16 * 1_048_576
    private static let резерв = 3 * 1_048_576

    static func хэшОбласти(_ область: ОбластьСписка) throws -> String {
        var исходная = область; исходная.команды = []; return try СписокРабот.хэш(исходная)
    }
    /// Хвост уже хэш-связан с предыдущими trace; не сериализуем растущий
    /// массив заново на каждом переносе. Полный смысл ядро проверит один раз.
    static func хэшСостояния(_ s: СостояниеСписка) throws -> String {
        try СписокРабот.хэш(ЯкорьСостоянияСписка(снимок: СписокРабот.хэш(s.снимок),
            хвост: s.цепочка.last.map(СписокРабот.хэш) ?? s.снимок.область, переходов: s.цепочка.count))
    }
    init(корень: URL, программа: ПрограммаПотребителяСписка, запись: Bool,
         создать: Bool = false, операции: ФайловыеОперации = .системные,
         сторона: ДовереннаяСторонаЭпохи? = nil) throws {
        try Self.проверить(программа)
        try требоватьСписок(корень.isFileURL && корень.path == корень.resolvingSymlinksInPath().standardizedFileURL.path &&
            корень.path != программа.наблюдение.дерево && !корень.path.hasPrefix(программа.наблюдение.дерево + "/"), "небезопасный-корень-данных")
        var сведения = stat()
        try требоватьСписок(lstat(корень.path, &сведения) == 0 && (сведения.st_mode & S_IFMT) == S_IFDIR &&
            сведения.st_uid == getuid() && (сведения.st_mode & 0o777) == 0o700, "нужен-собственный-каталог-0700")
        try требоватьСписок(!создать || (запись && программа.режим == .создать), "нет-явного-создания")
        let файл = корень.appendingPathComponent("сегмент.fumobs")
        if FileManager.default.fileExists(atPath: файл.path) {
            let размер = try файл.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? Self.пределДанных + 1
            try требоватьСписок(размер <= Self.пределДанных, "предел-данных")
        }
        // Невалидный host не создаёт даже genesis.
        let допуски = try Self.индексПоручений(сторона)
        let открытый = try Сегмент(кореньДанных: корень, запись: запись, создать: создать, операции: операции)
        do {
            try требоватьСписок(!открытый.естьХвост, "неполный-checkpoint-нужна-отдельная-процедура")
            var квитанции = открытый.записи
            if квитанции.isEmpty {
                try требоватьСписок(создать && программа.режим == .создать, "нет-checkpoint-не-begin")
                let начало = СохранённыйШагСписка(программа: программа,
                    состояние: try СписокРабот.начать(допуск: программа.допуск), решение: nil)
                let данные = try байтыСписка(начало)
                квитанции = [try открытый.добавить(Self.описание(программа, 0, false), данные: данные)]
            }
            try требоватьСписок(квитанции.count <= программа.пределСобытий + 1, "предел-checkpoint")
            var первичная: ПрограммаПотребителяСписка?
            // Один владелец растущей цепи: guard-копия целого состояния перед
            // append удерживала бы alias Array и вынуждала COW копировать prefix.
            // Это пока только чистая проекция; наличие genesis проверяется ниже.
            var текущее = try СписокРабот.начать(допуск: программа.допуск)
            var эпоха: ЭпохаСписка?
            var область: ОбластьСписка?
            var писатели = Set<String>()
            var хэшиПереходов: [String] = []
            var записи: [ЗапомненнаяЗаписьСписка] = []
            var обход = СчётчикиВосстановленияСписка()
            var началсяV2 = false
            var legacyХвост: Квитанция?
            for (номер, квитанция) in квитанции.enumerated() {
                обход.записей += 1
                try требоватьСписок(квитанция.размер <= 2 * 1_048_576, "предел-записи")
                let данные = try открытый.извлечь(квитанция.описание.идентификатор)
                let v2 = квитанция.описание.тип == "fum.worklist.delta.2"
                let p: ПрограммаПотребителяСписка
                let снимок: СнимокСписка
                var переход: ЗаписьПереходаСписка?
                var решение: РешениеСписка?
                var грант: ПоручениеПереносаЭпохи?
                var дельта: ДельтаСписка?
                if v2 {
                    началсяV2 = true
                    let d = try JSONDecoder().decode(ДельтаСписка.self, from: данные)
                    try требоватьСписок(d.версия == "fum.координация.delta-списка.2" && данные == байтыСписка(d), "подмена-v2")
                    p = d.программа; снимок = d.снимок; переход = d.переход; решение = d.решение; грант = d.поручение; дельта = d
                } else {
                    try требоватьСписок(!началсяV2, "downgrade-v1-после-v2")
                    let s = try JSONDecoder().decode(СохранённыйШагСписка.self, from: данные)
                    try требоватьСписок(s.версия == "fum.координация.checkpoint-списка.1" && s.ядро == СписокРабот.версия &&
                        данные == байтыСписка(s), "подмена-v1")
                    p = s.программа; снимок = s.состояние.снимок; решение = s.решение
                    try требоватьСписок(p.эпоха == nil && p.перенос == nil, "новые-поля-в-legacy")
                    if номер > 0 { legacyХвост = квитанция }
                    let цепь = s.состояние.цепочка
                    try требоватьСписок(цепь.count == хэшиПереходов.count + (номер == 0 ? 0 : 1), "неверная-длина-v1")
                    for (i, t) in цепь.enumerated() {
                        обход.legacyЭлементов += 1
                        if i < хэшиПереходов.count { try требоватьСписок(СписокРабот.хэш(t) == хэшиПереходов[i], "подмена-prefix-v1") }
                        else { переход = t }
                    }
                }
                try Self.проверить(p); try Self.связатьОбласть(p, программа)
                try требоватьСписок(квитанция.описание == Self.описание(p, номер, v2), "подмена-описания")
                if номер == 0 {
                    try требоватьСписок(!v2 && p.режим == .создать && решение == nil &&
                        снимок == СписокРабот.начать(допуск: p.допуск).снимок, "неверный-genesis")
                    первичная = p; текущее = СостояниеСписка(снимок: снимок)
                    эпоха = ЭпохаСписка(контекст: p.наблюдение); область = p.допуск.область; писатели.insert(p.наблюдение.писатель)
                } else {
                    guard let e = эпоха, let a = область, let genesis = первичная else {
                        throw ОшибкаПотребителяСписка.отказ("нет-genesis")
                    }
                    try Self.связатьОбласть(p, genesis)
                    try требоватьСписок(p.предыдущаяКвитанция == квитанции[номер - 1], "разрыв-квитанций")
                    if p.режим == .перенестиЭпоху {
                        guard let d = дельта, let g = грант else { throw ОшибкаПотребителяСписка.отказ("нет-переноса") }
                        let после = try Self.проверитьПеренос(p, g, e, текущее, a, квитанции[номер - 1], допуски, nil, false)
                        try требоватьСписок(d.эпохаДо == СписокРабот.хэш(e) && d.эпохаПосле == после &&
                            снимок == текущее.снимок && переход == nil && решение == nil, "перенос-меняет-worklist")
                        эпоха = после; писатели.insert(после.контекст.писатель); обход.переносов += 1
                    } else {
                        try Self.привязатьАктивную(p, e)
                        // V1 сохраняет исторический контракт admission. Новый V2
                        // не принимает дополнительные команды из stdin.
                        if v2 { try Self.связатьКоманды(p, a) }
                        guard let t = переход else { throw ОшибкаПотребителяСписка.отказ("нет-дельты") }
                        try Self.проверитьПереход(p, t, снимок, решение, текущее.снимок, хэшиПереходов)
                        if let d = дельта {
                            try требоватьСписок(d.эпохаДо == СписокРабот.хэш(e) && d.эпохаПосле == e && грант == nil, "подмена-эпохи-работой")
                        }
                        текущее.цепочка.append(t); текущее.снимок = снимок
                        хэшиПереходов.append(try СписокРабот.хэш(t)); область = p.допуск.область; обход.дельт += 1
                    }
                }
                записи.append(ЗапомненнаяЗаписьСписка(программа: p, данные: данные, квитанция: квитанция, поручение: грант))
            }
            guard let genesis = первичная, let e = эпоха, let a = область else {
                throw ОшибкаПотребителяСписка.отказ("нет-checkpoint")
            }
            let s = текущее // Чтение после последнего append; prefix больше не растёт.
            if let legacyХвост {
                try требоватьСписок(сторона?.принятыйLegacyХвост == legacyХвост, "нет-независимо-принятого-legacy-хвоста")
            }
            var допуск = ДопускСписка(область: a, контекст: e.контекст, писатели: писатели.sorted())
            if let t = s.цепочка.last {
                let проверено = try СписокРабот.переход(s, t.событие, допуск: допуск, контекст: e.контекст)
                try требоватьСписок(проверено.повтор && проверено.состояние == s, "неверный-финальный-replay")
            } else {
                допуск.контекст = genesis.наблюдение
                try требоватьСписок(s == СписокРабот.начать(допуск: допуск), "неверный-пустой-replay")
            }
            обход.полныхПроверокЯдра = 1
            if программа.режим != .перенестиЭпоху {
                try Self.привязатьАктивную(программа, e); try Self.связатьКоманды(программа, a)
            }
            if e.номер > 0 || программа.режим == .перенестиЭпоху {
                guard let host = сторона else { throw ОшибкаПотребителяСписка.отказ("нет-независимой-стороны") }
                if программа.режим != .перенестиЭпоху { try требоватьСписок(Self.совпадает(host.наблюдение, e), "неверное-наблюдение-host") }
            }
            self.сегмент = открытый; self.запись = запись; self.первичная = genesis; self.состояние = s
            self.эпоха = e; self.область = a; self.писатели = писатели; self.записи = записи; self.сторона = сторона; self.обход = обход
        } catch { открытый.закрыть(); throw error }
    }
    func принять(_ программа: ПрограммаПотребителяСписка, сторона новаяСторона: ДовереннаяСторонаЭпохи? = nil) throws -> ОтветПотребителяСписка {
        try доступ(); try требоватьСписок(запись, "только-чтение"); try Self.проверить(программа)
        try Self.связатьОбласть(программа, первичная)
        let host = новаяСторона ?? сторона
        let допуски = try Self.индексПоручений(host)
        let id = программа.режим == .перенестиЭпоху ? программа.перенос : программа.событие?.идентификатор
        try требоватьСписок(id?.isEmpty == false, "нет-ID")
        if let запись = записи.first(where: {
            $0.программа.режим == программа.режим &&
                ($0.программа.режим == .перенестиЭпоху ? $0.программа.перенос : $0.программа.событие?.идентификатор) == id
        }) {
            try требоватьСписок(байтыСписка(запись.программа) == байтыСписка(программа), "ID-с-другим-payload")
            if let g = запись.поручение {
                guard let подтверждённое = допуски[g.идентификатор] else { throw ОшибкаПотребителяСписка.отказ("нет-независимого-grant-повтора") }
                try требоватьСписок(СписокРабот.хэш(подтверждённое) == СписокРабот.хэш(g), "подмена-grant-повтора")
            }
            if эпоха.номер > 0 {
                guard let host else { throw ОшибкаПотребителяСписка.отказ("нет-host") }
                try требоватьСписок(Self.совпадает(host.наблюдение, эпоха), "устаревшая-incarnation")
            }
            do { _ = try сегмент.добавить(запись.квитанция.описание, данные: запись.данные) }
            catch { отказ = true; throw error }
            return ответ(безопасноеРешение(), true)
        }
        try требоватьСписок(программа.предыдущаяКвитанция == записи.last?.квитанция, "stale-или-нет-CAS")
        var новое = состояние, новаяЭпоха = эпоха
        var решение: РешениеСписка?, t: ЗаписьПереходаСписка?, g: ПоручениеПереносаЭпохи?
        if программа.режим == .перенестиЭпоху {
            guard let name = программа.перенос, let grant = допуски[name], let host else {
                throw ОшибкаПотребителяСписка.отказ("нет-независимого-поручения")
            }
            новаяЭпоха = try Self.проверитьПеренос(программа, grant, эпоха, состояние, область,
                записи[записи.count - 1].квитанция, допуски, host.наблюдение, true); g = grant
        } else {
            try Self.привязатьАктивную(программа, эпоха)
            try Self.связатьКоманды(программа, область)
            if эпоха.номер > 0 {
                guard let host else { throw ОшибкаПотребителяСписка.отказ("нет-host") }
                try требоватьСписок(Self.совпадает(host.наблюдение, эпоха), "устаревшее-наблюдение")
            }
            guard let event = программа.событие else { throw ОшибкаПотребителяСписка.отказ("нет-события") }
            if event.вид == .намерение && состояние.снимок.попытки.contains(where: { !$0.исходЗаписан }) {
                return ответ(безопасноеРешение(), true)
            }
            let admission = ДопускСписка(область: программа.допуск.область, контекст: эпоха.контекст, писатели: писатели.sorted())
            let result = try СписокРабот.переход(состояние, event, допуск: admission, контекст: эпоха.контекст)
            if result.повтор { return ответ(безопасноеРешение(), true) }
            новое = result.состояние; решение = result.решение; t = новое.цепочка.last
        }
        let stop = программа.событие?.вид == .остановить
        try требоватьСписок(записи.count - 1 < первичная.пределСобытий - (stop ? 0 : 1), "предел-с-резервом-STOP")
        try требоватьСписок(байтыСписка(новое).count <= 1_048_576 - (stop ? 0 : 131_072), "предел-проекции")
        let delta = ДельтаСписка(программа: программа, эпохаДо: try СписокРабот.хэш(эпоха), снимок: новое.снимок,
            переход: t, решение: решение, эпохаПосле: новаяЭпоха, поручение: g)
        let data = try байтыСписка(delta)
        let занято = записи.reduce(0) { $0 + $1.данные.count + 131_072 }
        try требоватьСписок(data.count <= 2 * 1_048_576 && занято + data.count + 131_072 <= Self.пределДанных - (stop ? 0 : Self.резерв), "предел-данных")
        let receipt: Квитанция
        do { receipt = try сегмент.добавить(Self.описание(программа, записи.count, true), данные: data) }
        catch { отказ = true; throw error }
        состояние = новое; эпоха = новаяЭпоха; писатели.insert(эпоха.контекст.писатель)
        if g == nil { область = программа.допуск.область }; сторона = host
        записи.append(ЗапомненнаяЗаписьСписка(программа: программа, данные: data, квитанция: receipt, поручение: g))
        return ответ(g == nil ? решение : безопасноеРешение(), false)
    }
    func прочитать() throws -> ОтветПотребителяСписка { try доступ(); return ответ(безопасноеРешение(), false) }
    func закрыть() { сегмент.закрыть(); отказ = true }
    private func доступ() throws { try требоватьСписок(!отказ, "UNKNOWN-нужно-close-reopen") }
    private func безопасноеРешение() -> РешениеСписка? {
        if состояние.снимок.остановлен { return РешениеСписка(вид: .остановлено) }
        if состояние.снимок.попытки.contains(where: { !$0.исходЗаписан }) { return РешениеСписка(вид: .неизвестно, препятствия: ["durable-intent-без-outcome"]) }
        return nil
    }
    private func ответ(_ решение: РешениеСписка?, _ повтор: Bool) -> ОтветПотребителяСписка {
        ОтветПотребителяСписка(схема: "fum.координация.ответ-потребителя-списка.1", квитанция: записи[записи.count - 1].квитанция,
            состояние: состояние, первичнаяОбласть: первичная.допуск.область, исходныеБайты: первичная.исходныеБайты!,
            решение: решение, повтор: повтор, толькоЧтение: !запись, эпоха: эпоха, обход: обход)
    }
    private static func совпадает(_ o: НаблюдениеЭпохи, _ e: ЭпохаСписка) -> Bool {
        o.контекст == e.контекст && o.код == e.код && o.модель == e.модель && o.усилие == e.усилие
    }
    private static func индексПоручений(_ host: ДовереннаяСторонаЭпохи?) throws -> [String: ПоручениеПереносаЭпохи] {
        var result: [String: ПоручениеПереносаЭпохи] = [:]
        for g in host?.поручения ?? [] {
            try требоватьСписок(result[g.идентификатор] == nil, "повтор-grant-ID"); result[g.идентификатор] = g
        }
        return result
    }
    private static func привязатьАктивную(_ p: ПрограммаПотребителяСписка, _ e: ЭпохаСписка) throws {
        try требоватьСписок(p.наблюдение == e.контекст && p.допуск.контекст == e.контекст &&
            (p.эпоха == (try СписокРабот.хэш(e)) || (e.номер == 0 && p.эпоха == nil)), "другой-активный-context")
    }
    private static func связатьОбласть(_ p: ПрограммаПотребителяСписка, _ a: ПрограммаПотребителяСписка) throws {
        try требоватьСписок(p.корневойUUID == a.корневойUUID && p.хэшОбласти == a.хэшОбласти && p.пределСобытий == a.пределСобытий, "другой-якорь-области")
    }
    private static func связатьКоманды(_ p: ПрограммаПотребителяСписка, _ domain: ОбластьСписка) throws {
        try требоватьСписок(СписокРабот.хэш(p.допуск.область) == СписокРабот.хэш(domain), "новые-команды-не-разрешены-checkpoint")
    }
    private static func проверитьПереход(_ p: ПрограммаПотребителяСписка, _ t: ЗаписьПереходаСписка,
        _ snapshot: СнимокСписка, _ decision: РешениеСписка?, _ before: СнимокСписка, _ hashes: [String]) throws {
        try требоватьСписок(p.режим == .применить && t.событие == p.событие && t.номер == hashes.count &&
            t.предыдущая == (hashes.last ?? before.область) && t.писатель == p.наблюдение.писатель &&
            t.версияКода == СписокРабот.версия && t.до == СписокРабот.хэш(before) && t.после == СписокРабот.хэш(snapshot) &&
            t.вход == СписокРабот.хэш(t.событие) && t.решение == decision && t.выход == СписокРабот.хэш(decision) &&
            t.команда == p.допуск.область.команды.first(where: { $0.идентификатор == t.событие.команда && $0.вид == t.событие.вид }).map(СписокРабот.хэш), "неверная-дельта")
    }
    private static func проверитьПеренос(_ p: ПрограммаПотребителяСписка, _ g: ПоручениеПереносаЭпохи,
        _ e: ЭпохаСписка, _ s: СостояниеСписка, _ domain: ОбластьСписка, _ receipt: Квитанция,
        _ grants: [String: ПоручениеПереносаЭпохи], _ observed: НаблюдениеЭпохи?, _ новый: Bool) throws -> ЭпохаСписка {
        guard let подтверждённое = grants[g.идентификатор] else { throw ОшибкаПотребителяСписка.отказ("нет-внешнего-grant") }
        try требоватьСписок(СписокРабот.хэш(подтверждённое) == СписокРабот.хэш(g) &&
            p.перенос == g.идентификатор && g.ROOT == p.корневойUUID && g.запросил == g.ROOT &&
            g.worklist == domain.идентификатор && g.область == p.хэшОбласти && g.предыдущаяКвитанция == receipt &&
            g.прежняяЭпоха == СписокРабот.хэш(e) && p.эпоха == g.прежняяЭпоха && g.состояние == хэшСостояния(s) &&
            g.наблюдение.контекст == p.наблюдение && СписокРабот.хэш(p.допуск.область) == СписокРабот.хэш(domain), "неподтверждённый-перенос")
        let o = g.наблюдение
        try требоватьСписок(o.контекст.дерево == e.контекст.дерево && o.контекст.реф == e.контекст.реф &&
            o.код.count == 64 && o.код.allSatisfy({ "0123456789abcdef".contains($0) }) &&
            !o.модель.isEmpty && !o.усилие.isEmpty && g.источник.коммит.count == 40 && g.источник.хэш.count == 64 &&
            (g.источник.коммит + g.источник.хэш).allSatisfy({ "0123456789abcdef".contains($0) }) &&
            !g.источник.путь.isEmpty && !g.источник.путь.hasPrefix("/") && !g.источник.путь.split(separator: "/").contains(".."), "неполный-перенос")
        if новый {
            try требоватьСписок(observed == o && !o.модель.lowercased().contains("astra") && o.модель.lowercased() != "gpt-5.6-sol", "неверное-наблюдение-или-модель")
        }
        switch g.вид {
        case .тотЖеHEAD: try требоватьСписок(o.контекст.коммит == e.контекст.коммит, "HEAD-не-тот-же")
        case .собственныйКоммит:
            try требоватьСписок(o.контекст.коммит != e.контекст.коммит && o.родители == [e.контекст.коммит], "не-собственный-commit")
        case .принятоеСлияние:
            guard let root = g.принятыйROOT else { throw ОшибкаПотребителяСписка.отказ("нет-принятого-ROOT") }
            try требоватьСписок(root.count == 40 && root.allSatisfy({ "0123456789abcdef".contains($0) }) && root != e.контекст.коммит && o.контекст.коммит != e.контекст.коммит &&
                o.родители == [e.контекст.коммит, root], "неверные-ordered-parents")
        }
        if o.контекст.писатель != e.контекст.писатель {
            try требоватьСписок(g.отзывПрежнегоПисателя?.count == 64 &&
                g.отзывПрежнегоПисателя?.allSatisfy({ "0123456789abcdef".contains($0) }) == true, "нет-отзыва-прежнего-писателя")
        }
        return ЭпохаСписка(номер: e.номер + 1, контекст: o.контекст, код: o.код, модель: o.модель,
            усилие: o.усилие, backend: "UNKNOWN", предыдущая: try СписокРабот.хэш(e), поручение: try СписокРабот.хэш(g))
    }
    private static func проверить(_ p: ПрограммаПотребителяСписка) throws {
        try требоватьСписок(p.схема == "fum.координация.программа-потребителя-списка.1" && p.пределСобытий > 0 && p.пределСобытий <= 128 &&
            UUID(uuidString: p.корневойUUID) != nil && p.наблюдение == p.допуск.контекст && p.допуск.писатели == [p.наблюдение.писатель] &&
            UUID(uuidString: p.наблюдение.писатель) != nil && p.наблюдение.писатель != p.корневойUUID && p.наблюдение.дерево.hasPrefix("/") &&
            p.наблюдение.реф.hasPrefix("refs/heads/") && p.наблюдение.коммит.count == 40 &&
            p.наблюдение.коммит.allSatisfy({ "0123456789abcdef".contains($0) }) &&
            p.хэшОбласти == хэшОбласти(p.допуск.область) && байтыСписка(p).count <= 65_536, "неполная-программа-допуск")
        _ = try СписокРабот.начать(допуск: p.допуск)
        if p.режим == .создать {
            try требоватьСписок(p.событие == nil && p.перенос == nil && p.эпоха == nil && p.предыдущаяКвитанция == nil &&
                p.исходныеБайты.map(хэшИсходника) == p.допуск.область.источник.хэш, "нет-точных-исходных-байтов")
        } else {
            try требоватьСписок(p.исходныеБайты == nil && (p.режим == .применить ? p.событие != nil && p.перенос == nil :
                p.событие == nil && (p.режим == .перенестиЭпоху ? p.перенос != nil && p.предыдущаяКвитанция != nil :
                    p.перенос == nil && p.предыдущаяКвитанция == nil)), "неверный-режим-входа")
        }
    }
    private static func описание(_ p: ПрограммаПотребителяСписка, _ номер: Int, _ v2: Bool) throws -> ОписаниеНаблюдения {
        ОписаниеНаблюдения(идентификатор: try СписокРабот.хэш(p), тип: v2 ? "fum.worklist.delta.2" : "fum.worklist.checkpoint.1",
            источник: p.хэшОбласти, время: "checkpoint-\(номер)", спецификация: Data(СписокРабот.версия.utf8))
    }
}

public enum КомандаПотребителяСписка {
    private static func git(_ args: [String], _ cwd: String) throws -> String {
        let p = Process(); p.executableURL = URL(fileURLWithPath: "/usr/bin/git"); p.arguments = ["--no-replace-objects"] + args
        p.currentDirectoryURL = URL(fileURLWithPath: cwd)
        var env = ProcessInfo.processInfo.environment.filter { !$0.key.hasPrefix("GIT_") }
        env["GIT_OPTIONAL_LOCKS"] = "0"; env["GIT_CONFIG_NOSYSTEM"] = "1"; env["GIT_CONFIG_GLOBAL"] = "/dev/null"; p.environment = env
        let out = Pipe(); p.standardOutput = out; p.standardError = FileHandle.nullDevice
        try p.run(); let data = out.fileHandleForReading.readDataToEndOfFile(); p.waitUntilExit()
        try требоватьСписок(p.terminationStatus == 0 && data.count < 16_384, "Git-наблюдение-недоступно")
        return String(decoding: data, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)
    }
    public static func выполнить() async -> Int32 {
        do {
            let args = CommandLine.arguments
            try требоватьСписок(args.count == 2 || (args.count == 5 && args[2] == "--допуск-эпохи"), "нужен-каталог-и-необязательный-host-допуск")
            var input = Data()
            while input.count <= 65_536 { let part = try FileHandle.standardInput.read(upToCount: 65_537 - input.count) ?? Data(); if part.isEmpty { break }; input.append(part) }
            try требоватьСписок(input.count <= 65_536, "предел-входа")
            let программа = try JSONDecoder().decode(ПрограммаПотребителяСписка.self, from: input)
            let cwd = URL(fileURLWithPath: FileManager.default.currentDirectoryPath).resolvingSymlinksInPath().path
            let context = КонтекстСписка(дерево: cwd, реф: try git(["symbolic-ref", "HEAD"], cwd),
                коммит: try git(["rev-parse", "HEAD"], cwd), писатель: ProcessInfo.processInfo.environment["CODEX_THREAD_ID"] ?? "")
            try требоватьСписок(context == программа.наблюдение && git(["rev-parse", "--show-toplevel"], cwd) == cwd, "не-сходится-live-Git-native-W")
            var сторона: ДовереннаяСторонаЭпохи?
            if args.count == 5 {
                let url = URL(fileURLWithPath: args[3]); var st = stat()
                try требоватьСписок(url.path == url.resolvingSymlinksInPath().path && lstat(url.path, &st) == 0 &&
                    (st.st_mode & S_IFMT) == S_IFREG && st.st_uid == getuid() && (st.st_mode & 0o777) == 0o600 && st.st_size <= 65_536, "небезопасный-host-допуск")
                let data = try Data(contentsOf: url)
                try требоватьСписок(хэшИсходника(data) == args[4], "host-SHA-не-сходится")
                let host = try JSONDecoder().decode(ДовереннаяСторонаЭпохи.self, from: data)
                let parents = try git(["show", "-s", "--format=%P", "HEAD"], cwd).split(separator: " ").map(String.init)
                let executable = URL(fileURLWithPath: args[0]).resolvingSymlinksInPath()
                try требоватьСписок(host.наблюдение.контекст == context && host.наблюдение.родители == parents &&
                    host.наблюдение.код == хэшИсходника(Data(contentsOf: executable)), "host-не-сходится-с-наблюдением")
                сторона = host // Модель/effort наблюдены host; backend из них не выводится.
            }
            let storage = try ХранилищеСпискаРабот(корень: URL(fileURLWithPath: args[1]), программа: программа,
                запись: программа.режим != .прочитать, создать: программа.режим == .создать, сторона: сторона)
            let answer: ОтветПотребителяСписка
            do {
                if программа.режим == .применить || программа.режим == .перенестиЭпоху { answer = try await storage.принять(программа, сторона: сторона) }
                else { answer = try await storage.прочитать() }
            } catch { await storage.закрыть(); throw error }
            await storage.закрыть(); try FileHandle.standardOutput.write(contentsOf: байтыСписка(answer) + Data([10])); return 0
        } catch { try? FileHandle.standardError.write(contentsOf: Data("UNKNOWN/отказ: \(error)\n".utf8)); return 1 }
    }
}

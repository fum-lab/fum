/// Память остаётся в прежнем worklist. Typed delivery payload — свидетельство
/// progress существующей позиции, а не дополнительный durable store/registry.
enum ПотребительДоставки {
    static func выполнить(корень: URL, допуск: ДопускДоставки, создать: Bool = false, толькоЧтение: Bool = false,
                          событие: СобытиеДоставки? = nil, стопКоманда: String? = nil) async throws -> ОтветДоставки {
        let начало = DispatchTime.now().uptimeNanoseconds
        _ = try ДоставкаАвтоматизаций.восстановить([], допуск: допуск)
        try требоватьДоставку(!(создать && толькоЧтение) && !(событие != nil && стопКоманда != nil) &&
            (!толькоЧтение || (событие == nil && стопКоманда == nil)), "неверный-режим")
        var проекция = допуск.программа
        проекция.режим = создать ? .создать : .прочитать
        if !создать { проекция.исходныеБайты = nil }
        проекция.событие = nil; проекция.предыдущаяКвитанция = nil; проекция.перенос = nil
        let файл = корень.appendingPathComponent("сегмент.fumobs")
        func размер() -> Int { ((try? FileManager.default.attributesOfItem(atPath: файл.path)[.size]) as? NSNumber)?.intValue ?? 0 }
        let до = размер()
        let хранилище = try ХранилищеСпискаРабот(корень: корень, программа: проекция, запись: !толькоЧтение,
            создать: создать, сторона: допуск.сторонаЭпохи)
        do {
            var ответ = try await хранилище.прочитать()
            var события = try ДоставкаАвтоматизаций.событияИзСнимка(ответ.состояние.снимок, план: допуск.план)
            var повторСобытия = false
            var метаданные: МетаданныеПолучателяДоставки?
            if let событие = событие {
                if let прежнее = события.first(where: { $0.идентификатор == событие.идентификатор }) {
                    try требоватьДоставку(прежнее == событие, "один-ID-разные-байты"); повторСобытия = true
                } else if !ответ.состояние.снимок.остановлен {
                    _ = try ДоставкаАвтоматизаций.восстановить(события + [событие], допуск: допуск)
                    if событие.вид == .намерение {
                        метаданные = try метаданныеДляОтправки(допуск, событие)
                        try требоватьДоставку(!допуск.требуетМетаданные || метаданные != nil, "metadata-UNKNOWN-при-обязательном-допуске")
                        try требоватьДоставку(событие.хэшМетаданных == метаданные.map { хэшДоставки(try байтыДоставки($0)) }, "intent-не-связан-с-metadata")
                        try требоватьДоставку(!ответ.состояние.снимок.попытки.contains { !$0.исходЗаписан }, "неизвестный-worklist-intent")
                    }
                    проекция.режим = .применить; проекция.исходныеБайты = nil; проекция.предыдущаяКвитанция = ответ.квитанция
                    проекция.событие = СобытиеСписка(идентификатор: "delivery:" + событие.идентификатор, вид: .прогресс,
                        обязательство: try ДоставкаАвтоматизаций.имяРаботы(допуск.план), свидетельство: String(decoding: try байтыДоставки(событие), as: UTF8.self))
                    // Только после успешного durable checkpoint разрешено выдать host действие.
                    ответ = try await хранилище.принять(проекция, сторона: допуск.сторонаЭпохи)
                    события = try ДоставкаАвтоматизаций.событияИзСнимка(ответ.состояние.снимок, план: допуск.план)
                }
            }
            if let команда = стопКоманда {
                проекция.режим = .применить; проекция.исходныеБайты = nil; проекция.предыдущаяКвитанция = ответ.квитанция
                проекция.событие = СобытиеСписка(идентификатор: "delivery-stop:" + команда, вид: .остановить, команда: команда)
                ответ = try await хранилище.принять(проекция, сторона: допуск.сторонаЭпохи)
            }
            let проекцияДоставки = try ДоставкаАвтоматизаций.восстановить(события, допуск: допуск)
            let ожидаетсяИсходЯдра = ответ.состояние.снимок.попытки.contains { !$0.исходЗаписан }
            let агрегат = АгрегатДоставки(план: допуск.план, квитанция: ответ.квитанция, получатели: проекцияДоставки.получатели,
                остановлен: ответ.состояние.снимок.остановлен,
                полныйОхват: !ожидаетсяИсходЯдра && ДоставкаАвтоматизаций.полныйОхват(проекцияДоставки.получатели, допуск: допуск, остановлен: ответ.состояние.снимок.остановлен))
            let новыйIntent = событие?.вид == .намерение && !повторСобытия && !ответ.состояние.снимок.остановлен && !ожидаетсяИсходЯдра
            let неизвестно = проекцияДоставки.получатели.contains { $0.попытка != nil && !$0.исходОтправки } || ожидаетсяИсходЯдра
            let действие = агрегат.остановлен ? "STOP" : новыйIntent ? "передать-host" : неизвестно ? "UNKNOWN" : агрегат.полныйОхват ? "покрыт-закреплённый-охват" : "ждать-следующего-свидетельства"
            await хранилище.закрыть()
            return ОтветДоставки(агрегат: агрегат, действие: действие, командаДляHost: новыйIntent ? событие : nil,
                метаданные: метаданные, статусМетаданных: метаданные == nil ? "UNKNOWN" : "selected-observed/backend-UNKNOWN", повтор: повторСобытия,
                счётчики: проекцияДоставки.счётчики, байтовСегментаДо: до, байтовСегментаПосле: размер(),
                наносекунд: DispatchTime.now().uptimeNanoseconds - начало)
        } catch { await хранилище.закрыть(); throw error }
    }
    private static func метаданныеДляОтправки(_ допуск: ДопускДоставки, _ событие: СобытиеДоставки) throws -> МетаданныеПолучателяДоставки? {
        guard let метаданные = допуск.метаданные[событие.получатель] else { return nil }
        let цель = метаданные.контекст
        try требоватьДоставку(цель.корневойUUID == допуск.программа.корневойUUID && цель.сессия == допуск.идентичностиУзлов[событие.получатель] &&
            цель.непосредственныйРодитель == допуск.идентичностиУзлов[допуск.план.родитель] && цель.попытка == событие.попытка && цель.этап == допуск.этап &&
            ГенераторМетаданныхКоммита.проверитьReceipt(метаданные.пара.фактическая, ожидаемый: метаданные.пара.ожидаемая,
                expectedRootUUID: допуск.программа.корневойUUID, ожидаемыйДочернийКонтекст: цель).isEmpty, "metadata-не-связаны-с-получателем-попыткой")
        return метаданные
    }
}


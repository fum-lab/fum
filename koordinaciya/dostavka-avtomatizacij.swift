enum ДоставкаАвтоматизаций {
    static func имяРаботы(_ план: ПланДоставки) throws -> String { "доставка:" + хэшДоставки(try байтыДоставки(план)) }
    static func хэшВерный(_ хэш: String, длина: Int = 64) -> Bool {
        хэш.count == длина && хэш.allSatisfy { "0123456789abcdef".contains($0) }
    }
    static func идентификатор(_ план: ПланДоставки, _ получатель: String) throws -> String {
        struct Ребро: Encodable { let источник: ИсточникДоставки; let родитель: String; let получатель: ПолучательДоставки }
        guard let цель = план.дети.first(where: { $0.узел == получатель }) else { throw ОшибкаДоставки.отказ("не-прямой-ребёнок") }
        return хэшДоставки(try байтыДоставки(Ребро(источник: план.источник, родитель: план.родитель, получатель: цель)))
    }
    static func восстановить(_ события: [СобытиеДоставки], допуск: ДопускДоставки) throws -> ПроекцияДоставки {
        var остатокОбхода = 128
        return try восстановитьОграниченно(события, допуск: допуск, остаток: &остатокОбхода)
    }
    private static func восстановитьОграниченно(_ события: [СобытиеДоставки], допуск: ДопускДоставки, остаток: inout Int) throws -> ПроекцияДоставки {
        try проверитьПлан(допуск)
        try требоватьДоставку(события.count <= 127, "предел-событий")
        var счётчики = СчётчикиДоставки()
        var свидетельства: [String: (НаблюдениеПолучателяДоставки, ПроверенноеСвидетельствоДоставки)] = [:]
        for запись in допуск.проверенные {
            try требоватьДоставку(запись.байты.count <= 65_536 && хэшВерный(запись.хэш) &&
                хэшДоставки(запись.байты) == запись.хэш && свидетельства[запись.хэш] == nil, "свидетельство-хэш-или-повтор")
            let наблюдение = try JSONDecoder().decode(НаблюдениеПолучателяДоставки.self, from: запись.байты)
            try требоватьДоставку(UUID(uuidString: запись.ожидаемыйИсполнитель) != nil && наблюдение.исполнитель == запись.ожидаемыйИсполнитель,
                "нет-независимого-actor-свидетельства")
            свидетельства[запись.хэш] = (наблюдение, запись)
            счётчики.прочитаноБайт += запись.байты.count; счётчики.хэшированоБайт += запись.байты.count
        }
        var проекции = try допуск.план.дети.map {
            ПроекцияПолучателяДоставки(доставка: try идентификатор(допуск.план, $0.узел), получатель: $0.узел)
        }
        let номера = Dictionary(uniqueKeysWithValues: проекции.enumerated().map { ($1.получатель, $0) })
        var встречены: [String: СобытиеДоставки] = [:]
        for событие in события {
            try требоватьДоставку(остаток > 0, "общий-предел-рекурсивного-обхода"); остаток -= 1
            let байты = try байтыДоставки(событие)
            счётчики.событий += 1; счётчики.прочитаноБайт += байты.count
            try требоватьДоставку(!событие.идентификатор.isEmpty && байты.count <= 32_768, "пустой-ID-или-предел")
            if let прежнее = встречены[событие.идентификатор] {
                try требоватьДоставку(прежнее == событие, "один-ID-разные-байты"); continue
            }
            встречены[событие.идентификатор] = событие
            guard let номер = номера[событие.получатель] else { throw ОшибкаДоставки.отказ("не-прямой-ребёнок") }
            let цель = допуск.план.дети[номер]
            // Адресный grant закрепляет отдельные задачи/области в конечном плане.
            // Веточное обновление сохраняет прежнюю узкую selfupdate область.
            let несовместимо = цель.совместимость != допуск.план.источник.совместимость ||
                (допуск.план.источник.вид == .веточноеОбновление && цель.область != допуск.план.источник.область)
            // Один изменяемый элемент; растущих массивов в проекции ребра нет.
            var проекция = проекции[номер]
            var наблюдение: НаблюдениеПолучателяДоставки?
            var оригинал: ПроверенноеСвидетельствоДоставки?
            if let отпечаток = событие.свидетельство {
                guard let (проверенноеНаблюдение, сырыеБайты) = свидетельства[отпечаток] else { throw ОшибкаДоставки.отказ("нет-независимого-свидетельства") }
                try требоватьДоставку(проверенноеНаблюдение.доставка == проекция.доставка && проверенноеНаблюдение.родитель == допуск.план.родитель && проверенноеНаблюдение.получатель == цель.узел &&
                    проверенноеНаблюдение.версия == допуск.план.источник.версия && проверенноеНаблюдение.источник == допуск.план.источник.хэш && проверенноеНаблюдение.вид == событие.вид,
                    "чужое-свидетельство-версии-ребра")
                наблюдение = проверенноеНаблюдение; оригинал = сырыеБайты; счётчики.провереноСвидетельств += 1
            }
            switch событие.вид {
            case .доступно: проекция.доступно = true
            case .заявление:
                try требоватьДоставку(!событие.текст.isEmpty, "пустое-заявление"); проекция.заявлений += 1
                проекция.причина = "непроверенное-заявление"
                проекция.вернутьВнимание = "точная квитанция от " + допуск.план.источник.производитель
            case .пауза, .возобновить, .отзыв:
                счётчики.хэшированоБайт += байты.count
                try требоватьДоставку(допуск.управления.contains(хэшДоставки(байты)) && !событие.текст.isEmpty, "нет-адресного-управления")
                if событие.вид == .отзыв { проекция.отозвано = true }
                else { проекция.пауза = событие.вид == .пауза }
                проекция.причина = событие.текст
            case .намерение:
                try требоватьДоставку(!несовместимо && !проекция.пауза && !проекция.отозвано && событие.попытка?.isEmpty == false,
                    "неприменимо-пауза-отзыв")
                if проекция.попытка != nil {
                    счётчики.хэшированоБайт += байты.count
                    try требоватьДоставку(проекция.исходОтправки && проекция.принятоAPI == false && проекция.попытка != событие.попытка &&
                        допуск.управления.contains(хэшДоставки(байты)), "неизвестный-исход-или-слепой-повтор")
                }
                проекция.доступно = true; проекция.попытка = событие.попытка; проекция.исходОтправки = false; проекция.принятоAPI = nil
            case .отправка:
                guard let наблюдение = наблюдение else { throw ОшибкаДоставки.отказ("отправка-без-receipt") }
                try требоватьДоставку(проекция.попытка != nil && !проекция.исходОтправки && наблюдение.попытка == проекция.попытка &&
                    событие.попытка == проекция.попытка && наблюдение.исполнитель == допуск.идентичностиУзлов[допуск.план.родитель], "outcome-без-своего-intent")
                проекция.исходОтправки = true; проекция.принятоAPI = наблюдение.принятоAPI
            case .собственныйACK:
                guard let наблюдение = наблюдение else { throw ОшибкаДоставки.отказ("ACK-без-receipt") }
                try требоватьДоставку(наблюдение.исполнитель != допуск.идентичностиУзлов[допуск.план.родитель], "ACK-подписан-родителем")
                try требоватьДоставку(наблюдение.исполнитель == допуск.идентичностиУзлов[цель.узел], "ACK-чужой-incarnation")
                if проекция.собственныйACK != наблюдение.исполнитель { проекция.применимость = nil; проекция.использовал = nil; проекция.дочернийАгрегат = nil }
                проекция.собственныйACK = наблюдение.исполнитель
            case .применимость:
                guard let наблюдение = наблюдение else { throw ОшибкаДоставки.отказ("применимость-без-receipt") }
                try требоватьДоставку(проекция.собственныйACK == наблюдение.исполнитель && наблюдение.применимо != nil &&
                    (наблюдение.применимо == true || (!наблюдение.причина.isEmpty && !наблюдение.вернутьВнимание.isEmpty)), "нет-ownACK-или-причины")
                проекция.применимость = наблюдение.применимо; проекция.причина = наблюдение.причина; проекция.вернутьВнимание = наблюдение.вернутьВнимание
            case .использование:
                guard let наблюдение = наблюдение, let команда = наблюдение.команда else { throw ОшибкаДоставки.отказ("usage-без-команды") }
                try требоватьДоставку(!несовместимо && !проекция.пауза && !проекция.отозвано && проекция.собственныйACK == наблюдение.исполнитель && проекция.применимость == true &&
                    допуск.разрешённыеИспользования.contains(where: { $0.идентификатор == команда.разрешение && $0.аргументы == команда.аргументы && $0.вход == команда.вход }) && хэшВерный(команда.разрешение) &&
                    !команда.аргументы.isEmpty && команда.аргументы.allSatisfy({ !$0.isEmpty }) &&
                    [команда.вход, команда.stdout, команда.stderr].allSatisfy({ хэшВерный($0) }), "usage-не-связан-с-ACK-допуском-исходом")
                проекция.использовал = наблюдение.исполнитель; проекция.кодИспользования = команда.код
            case .агрегат:
                guard let наблюдение = наблюдение, let агрегат = наблюдение.агрегат, let контрольнаяТочка = оригинал?.контрольнаяТочка,
                      let проверка = оригинал?.дочерняяПроверка else {
                    throw ОшибкаДоставки.отказ("агрегат-без-связанного-checkpoint")
                }
                var план = допуск.план; план.родитель = цель.узел; план.дети = цель.дети
                try требоватьДоставку(проекция.собственныйACK == наблюдение.исполнитель && агрегат.план == план &&
                    агрегат.квитанция.размер == контрольнаяТочка.count && агрегат.квитанция.хэш == хэшДоставки(контрольнаяТочка), "подмена-дочернего-агрегата")
                let дельта = try JSONDecoder().decode(ДельтаСписка.self, from: контрольнаяТочка)
                let ответ = проверка.ответ
                try требоватьДоставку(проверка.квитанция == агрегат.квитанция && ответ.квитанция == проверка.квитанция &&
                    проверка.допуск.контекст.писатель == наблюдение.исполнитель && проверка.допуск.контекст == дельта.программа.наблюдение &&
                    проверка.допуск.область == ответ.первичнаяОбласть && дельта.снимок == ответ.состояние.снимок &&
                    проверка.область == дельта.программа.хэшОбласти && проверка.область == ХранилищеСпискаРабот.хэшОбласти(ответ.первичнаяОбласть) &&
                    проверка.состояние == ХранилищеСпискаРабот.хэшСостояния(ответ.состояние) &&
                    проверка.эпоха == ответ.эпоха.map(СписокРабот.хэш) &&
                    хэшДоставки(ответ.исходныеБайты) == ответ.первичнаяОбласть.источник.хэш, "нет-независимого-child-replay")
                if let последний = ответ.состояние.цепочка.last {
                    let восстановлено = try СписокРабот.переход(ответ.состояние, последний.событие, допуск: проверка.допуск, контекст: проверка.допуск.контекст)
                    try требоватьДоставку(восстановлено.повтор && восстановлено.состояние == ответ.состояние, "неверный-child-core-replay")
                } else {
                    try требоватьДоставку(ответ.состояние == СписокРабот.начать(допуск: проверка.допуск), "неверный-пустой-child-replay")
                }
                var дочернийДопуск = допуск; дочернийДопуск.план = план; дочернийДопуск.программа = дельта.программа
                дочернийДопуск.самообновлениеJSON = проверка.самообновлениеJSON
                let дочерниеСобытия = try событияИзСнимка(дельта.снимок, план: план)
                let ребёнок = try восстановитьОграниченно(дочерниеСобытия, допуск: дочернийДопуск, остаток: &остаток)
                try требоватьДоставку(агрегат.получатели == ребёнок.получатели && агрегат.остановлен == дельта.снимок.остановлен &&
                    агрегат.полныйОхват == (!дельта.снимок.попытки.contains { !$0.исходЗаписан } &&
                        полныйОхват(ребёнок.получатели, допуск: дочернийДопуск, остановлен: агрегат.остановлен)), "неверная-проекция-дочернего-агрегата")
                проекция.дочернийАгрегат = агрегат; счётчики.прочитаноБайт += контрольнаяТочка.count; счётчики.хэшированоБайт += контрольнаяТочка.count
                счётчики.событий += ребёнок.счётчики.событий; счётчики.провереноСвидетельств += ребёнок.счётчики.провереноСвидетельств
                счётчики.прочитаноБайт += ребёнок.счётчики.прочитаноБайт; счётчики.хэшированоБайт += ребёнок.счётчики.хэшированоБайт
            }
            if несовместимо { проекция.причина = "несовместимость-задачи-области"; проекция.вернутьВнимание = "адресный совместимый источник" }
            проекции[номер] = проекция
        }
        return ПроекцияДоставки(получатели: проекции, счётчики: счётчики)
    }
    static func событияИзСнимка(_ снимок: СнимокСписка, план: ПланДоставки) throws -> [СобытиеДоставки] {
        guard let работа = снимок.позиции.first(where: { $0.описание.идентификатор == (try? имяРаботы(план)) }) else {
            throw ОшибкаДоставки.отказ("нет-первичного-worklist-доставки")
        }
        return try работа.свидетельства.map {
            try требоватьДоставку($0.hasPrefix("прогресс:"), "чужое-свидетельство-worklist")
            return try JSONDecoder().decode(СобытиеДоставки.self, from: Data($0.dropFirst("прогресс:".count).utf8))
        }
    }
    static func полныйОхват(_ проекции: [ПроекцияПолучателяДоставки], допуск: ДопускДоставки, остановлен: Bool) -> Bool {
        !остановлен && допуск.план.полныйИзвестныйОхват && проекции.count == допуск.план.дети.count && проекции.allSatisfy { проекция in
            let дети = допуск.план.дети.first { $0.узел == проекция.получатель }?.дети ?? []
            return !проекция.пауза && !проекция.отозвано && проекция.исходОтправки && проекция.собственныйACK == допуск.идентичностиУзлов[проекция.получатель] &&
                проекция.применимость == true && проекция.использовал == проекция.собственныйACK &&
                (дети.isEmpty || проекция.дочернийАгрегат?.полныйОхват == true)
        }
    }
    private static func проверитьПлан(_ допуск: ДопускДоставки) throws {
        let проекция = допуск.план, источник = проекция.источник
        try требоватьДоставку(проекция.схема == "fum.координация.доставка.1" && !источник.репозиторий.isEmpty && !источник.версия.isEmpty && !источник.производитель.isEmpty &&
            хэшВерный(источник.хэш) && хэшВерный(источник.коммитКонтекста, длина: 40) && !источник.область.isEmpty && !источник.совместимость.isEmpty &&
            !проекция.родитель.isEmpty && допуск.идентичностиУзлов[проекция.родитель] == допуск.программа.наблюдение.писатель, "неполный-план-или-родитель")
        let работа = try имяРаботы(проекция)
        try требоватьДоставку(допуск.проверенные.count <= 128 && допуск.проверенные.reduce(0, { $0 + $1.байты.count }) <= 1_048_576, "предел-свидетельств")
        try требоватьДоставку(!допуск.этап.isEmpty && допуск.программа.допуск.область.обязательства.contains {
            $0.идентификатор == работа && $0.тип == "доставка" && $0.критерий == работа
        }, "план-не-закреплён-в-worklist")
        var узлы = Set([проекция.родитель])
        func дерево(_ дети: [ПолучательДоставки], _ глубина: Int) throws {
            try требоватьДоставку(глубина <= 8, "предел-глубины")
            for цель in дети {
                try требоватьДоставку(узлы.count < 33 && !цель.узел.isEmpty && !цель.задача.isEmpty && !цель.область.isEmpty && !цель.совместимость.isEmpty && узлы.insert(цель.узел).inserted &&
                    допуск.идентичностиУзлов[цель.узел].flatMap(UUID.init(uuidString:)) != nil, "неполное-дерево-или-повтор")
                try дерево(цель.дети, глубина + 1)
            }
        }
        try дерево(проекция.дети, 1)
        let идентичности = узлы.compactMap { допуск.идентичностиУзлов[$0] }
        try требоватьДоставку(Set(идентичности).count == узлы.count, "одна-incarnation-два-узла")
        if источник.вид == .адресноеРешение {
            try требоватьДоставку(источник.коммитИсточника == nil && источник.путьИсточника == nil && допуск.самообновлениеJSON == nil, "адресный-grant-не-Git-merge")
        } else {
            guard let коммит = источник.коммитИсточника, let путь = источник.путьИсточника, let сырыеБайты = допуск.самообновлениеJSON else {
                throw ОшибкаДоставки.отказ("нет-веточного-selfupdate")
            }
            let план = try JSONDecoder().decode(ПланСамообновления.self, from: сырыеБайты)
            let результат = ОценщикСамообновления.оценить(план, ожидаемыйКорневойUUID: допуск.программа.корневойUUID)
            try требоватьДоставку(хэшВерный(коммит, длина: 40) && !путь.hasPrefix("/") && !путь.split(separator: "/").contains("..") &&
                результат.ошибкиПлана.isEmpty && !результат.решенияИсточников.isEmpty && результат.решенияИсточников.allSatisfy { $0.решение == .подтверждено && $0.ошибки.isEmpty } &&
                план.источники.contains { $0.источникOID == коммит && $0.область == источник.область }, "веточное-самообновление-не-подтверждено")
        }
    }

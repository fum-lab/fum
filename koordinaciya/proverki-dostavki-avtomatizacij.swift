private func свидетельство(_ допуск: inout ДопускДоставки, _ вид: ВидСобытияДоставки, _ идентификатор: String,
                           получатель: String = "ребёнок", изменить: (inout НаблюдениеПолучателяДоставки) -> Void = { _ in }) throws -> СобытиеДоставки {
    let исполнитель = try #require(допуск.идентичностиУзлов[вид == .отправка ? допуск.план.родитель : получатель])
    var наблюдение = НаблюдениеПолучателяДоставки(доставка: try ДоставкаАвтоматизаций.идентификатор(допуск.план, получатель),
        родитель: допуск.план.родитель, получатель: получатель, исполнитель: исполнитель, версия: допуск.план.источник.версия, источник: допуск.план.источник.хэш, вид: вид)
    изменить(&наблюдение)
    let данные = try байтыДоставки(наблюдение), отпечаток = хэшДоставки(данные)
    допуск.проверенные.append(ПроверенноеСвидетельствоДоставки(хэш: отпечаток, байты: данные, ожидаемыйИсполнитель: исполнитель))
    return СобытиеДоставки(идентификатор: идентификатор, получатель: получатель, вид: вид, попытка: наблюдение.попытка, свидетельство: отпечаток)
}
private func полныйЭпизод(_ допуск: inout ДопускДоставки, _ получатель: String = "ребёнок") throws -> [СобытиеДоставки] {
    let поручение = String(repeating: "c", count: 64)
    let разрешение = РазрешённоеИспользованиеДоставки(идентификатор: поручение, аргументы: ["разрешённая-фикстура", "--вход", "fixture"], вход: String(repeating: "d", count: 64))
    if !допуск.разрешённыеИспользования.contains(разрешение) { допуск.разрешённыеИспользования.append(разрешение) }
    let намерение = СобытиеДоставки(идентификатор: "intent-" + получатель, получатель: получатель, вид: .намерение, попытка: "attempt-" + получатель)
    let отправлено = try свидетельство(&допуск, .отправка, "sent-" + получатель, получатель: получатель) { $0.попытка = намерение.попытка; $0.принятоAPI = true }
    let подтверждено = try свидетельство(&допуск, .собственныйACK, "ack-" + получатель, получатель: получатель)
    let применимость = try свидетельство(&допуск, .применимость, "applicable-" + получатель, получатель: получатель) { $0.применимо = true }
    let использовано = try свидетельство(&допуск, .использование, "used-" + получатель, получатель: получатель) {
        $0.команда = КомандаИспользованияДоставки(разрешение: поручение, аргументы: ["разрешённая-фикстура", "--вход", "fixture"],
            вход: String(repeating: "d", count: 64), код: 1, stdout: хэшДоставки(Data()), stderr: хэшДоставки(Data("Ожидаемый RED".utf8)))
    }
    return [намерение, отправлено, подтверждено, применимость, использовано]
}
private func каталогДоставки(_ имя: String) throws -> URL {
    let корень = try #require(ProcessInfo.processInfo.environment["КАТАЛОГ_ФИКСТУР"])
    let адрес = URL(fileURLWithPath: корень).appendingPathComponent(имя)
    try FileManager.default.createDirectory(at: адрес, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
    return адрес
}

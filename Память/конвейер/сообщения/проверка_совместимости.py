class Несовместимость(ValueError):
    """Закрытый отказ без изменения исходных данных."""


def требовать(условие, причина):
    if not условие:
        raise Несовместимость(причина)


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def полный_объект(значение):
    требовать(type(значение) is str and re.fullmatch(r"[0-9a-f]{40}", значение), "Нужен полный OID Git")
    return значение


def без_повторов(пары):
    результат = {}
    for ключ, значение in пары:
        требовать(ключ not in результат, "Повторный ключ JSON")
        результат[ключ] = значение
    return результат


def недопустимое_число(значение):
    raise Несовместимость("Недопустимое число JSON")


def прочитать_объект(байты):
    try:
        значение = json.loads(байты.decode("utf-8"), object_pairs_hook=без_повторов, parse_constant=недопустимое_число)
    except (UnicodeError, json.JSONDecodeError) as ошибка:
        raise Несовместимость("Повреждённый UTF-8 JSON") from ошибка
    требовать(type(значение) is dict, "Ожидался объект JSON")
    return значение


def прочитать_строки(байты):
    требовать(type(байты) is bytes and байты.endswith(b"\n"), "JSONL должен завершаться полным LF")
    строки = байты.split(b"\n")[:-1]
    требовать(len(строки) == 7 and all(строки), "Ожидалось ровно семь полных строк")
    return [прочитать_объект(строка) for строка in строки]


def равны(первое, второе):
    if type(первое) is not type(второе):
        return False
    if type(первое) is dict:
        return первое.keys() == второе.keys() and all(равны(первое[ключ], второе[ключ]) for ключ in первое)
    if type(первое) is list:
        return len(первое) == len(второе) and all(равны(левое, правое) for левое, правое in zip(первое, второе))
    return первое == второе


def сверить_поток(эталон, поток, свидетельство):
    требовать(len(эталон) == 5790 and хэш(эталон) == ХЭШ_ПОТОКА, "Не тот публичный контрольный вход")
    прочитать_строки(эталон)
    требовать(поток == эталон, "Поток событий не совпал со всеми байтами входа")
    ожидаемое = {
        "схема": "fum.свидетельство-потока-пилота.1", "вход": ПУТЬ_ВХОДА,
        "вход_sha256": хэш(эталон), "результат_sha256": хэш(поток),
        "байтов": len(поток), "строк": len(поток.split(b"\n")) - 1,
    }
    требовать(равны(прочитать_объект(свидетельство), ожидаемое), "Неверное точное свидетельство потока")
    return {"байтов": len(поток), "строк": 7, "sha256": хэш(поток), "свидетельство_sha256": хэш(свидетельство)}


def сверить_записи(вход, сообщения, связи, исходники):
    исходные = прочитать_строки(вход)
    готовые = прочитать_строки(сообщения)
    ожидаемые_связи = {"схема": "fum.связи-происхождения-пилота.1", "поток_sha256": хэш(вход), "идентичности": ИДЕНТИЧНОСТИ}
    требовать(равны(прочитать_объект(связи), ожидаемые_связи), "Не совпали связи происхождения")
    диапазоны = []
    for номер, (исходная, готовая) in enumerate(zip(исходные, готовые), 1):
        требовать(set(исходная) == {"схема", "номер", "идентичность", "роль", "текст", "исходник"}, "Неверные поля входной записи")
        требовать(исходная["схема"] == "fum.пилот-события.1", "Неверная схема входа")
        требовать(type(исходная["номер"]) is int and исходная["номер"] == номер, "Не совпал номер входа")
        требовать(исходная["идентичность"] == ИДЕНТИЧНОСТИ[номер - 1], "Не совпал порядок идентичностей")
        роль = "пользователь" if номер <= 4 else "ассистент"
        требовать(исходная["роль"] == роль and type(исходная["текст"]) is str, "Неверные роль или текст входа")
        поля = {"идентичность", "роль", "текст", "исходник", "вид", "исполнение_доказано"}
        требовать(set(готовая) in (поля, поля | {"номер"}), "Неверные поля готовой записи")
        for поле in ("идентичность", "роль", "текст", "исходник"):
            требовать(равны(готовая[поле], исходная[поле]), "Не совпало поле сообщения: " + поле)
        if "номер" in готовая:
            требовать(равны(готовая["номер"], исходная["номер"]), "Не совпал сохранённый номер")
        требовать(готовая["вид"] == КЛАССЫ[номер - 1], "Не совпала классификация")
        требовать(type(готовая["исполнение_доказано"]) is bool and готовая["исполнение_доказано"] is False, "Исполнение требует boolean false")
        происхождение = исходная["исходник"]
        требовать(type(происхождение) is dict and set(происхождение) == {"путь", "начало", "конец", "sha256", "формат"}, "Неполный исходник")
        путь, начало, конец = происхождение["путь"], происхождение["начало"], происхождение["конец"]
        требовать(type(путь) is str and путь in исходники, "Недоступен публичный исходник из C")
        байты = исходники[путь]
        требовать(type(начало) is int and type(конец) is int and 0 <= начало < конец <= len(байты), "Неверный исходный диапазон")
        диапазон = байты[начало:конец]
        требовать(хэш(диапазон) == происхождение["sha256"], "SHA256 исходного диапазона не совпал")
        if происхождение["формат"] == "текст":
            требовать(диапазон == исходная["текст"].encode("utf-8"), "Не совпал дословный текст диапазона")
        elif происхождение["формат"] == "ответ-jsonl":
            требовать(диапазон.endswith(b"\n") and диапазон.count(b"\n") == 1 and (начало == 0 or байты[начало - 1:начало] == b"\n"), "Диапазон ответа должен включать LF полной строки")
            ответ = прочитать_объект(диапазон)
            требовать(равны(ответ.get("текст"), исходная["текст"]), "Не совпал текст опубликованного ответа")
        else:
            raise Несовместимость("Неизвестный формат исходника")
        диапазоны.append({"идентичность": исходная["идентичность"], "исходник": dict(происхождение), "LF_проверен": происхождение["формат"] == "ответ-jsonl"})
    return {"записей": 7, "диапазонов": len(диапазоны), "идентичности": list(ИДЕНТИЧНОСТИ),
            "порядок": True, "номера": True, "роли": True, "дословные_тексты": True,
            "полные_исходники": True, "классификация": True, "boolean_false": True,
            "исходные_диапазоны": диапазоны, "исполнение_доказано": False}


class ЧитательGit:
    """Каждый commit и blob читается не более одного раза за проход."""

    def __init__(self, корень):
        self.корень = Path(корень)
        требовать(self.корень.is_absolute() and self.корень.resolve() == self.корень, "Нужен физический абсолютный корень")
        self.коммиты = {}
        self.записи = {}
        self.байты = {}
        self.вызовов = 0

    def выполнить(self, *аргументы):
        self.вызовов += 1
        try:
            return subprocess.run(["git", "--no-replace-objects", "-c", "core.fsmonitor=false", "-C", str(self.корень), *аргументы],
                                  stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True, timeout=30).stdout
        except (OSError, subprocess.SubprocessError) as ошибка:
            raise Несовместимость("Git не подтвердил закреплённые объекты или наблюдение") from ошибка

    def коммит(self, объект):
        полный_объект(объект)
        if объект not in self.коммиты:
            требовать(self.выполнить("cat-file", "-t", объект) == b"commit\n", "OID не является коммитом")
            заголовок = self.выполнить("cat-file", "-p", объект).split(b"\n\n", 1)[0].decode("utf-8")
            деревья = [строка[5:] for строка in заголовок.splitlines() if строка.startswith("tree ")]
            родители = [строка[7:] for строка in заголовок.splitlines() if строка.startswith("parent ")]
            требовать(len(деревья) == 1, "Неверное дерево коммита")
            self.коммиты[объект] = {"OID": объект, "tree": полный_объект(деревья[0]), "родители": [полный_объект(родитель) for родитель in родители]}
        return self.коммиты[объект]

    def запись(self, объект, путь):
        ключ = (полный_объект(объект), путь)
        if ключ not in self.записи:
            строки = self.выполнить("ls-tree", "-z", объект, "--", путь).split(b"\0")
            требовать(len(строки) == 2 and строки[-1] == b"", "Нет единственного файла в Git-объекте")
            заголовок, имя = строки[0].split(b"\t", 1)
            режим, тип, blob = заголовок.decode("ascii").split()
            требовать(имя.decode("utf-8") == путь and тип == "blob" and режим in ("100644", "100755"), "Ожидался обычный Git-файл")
            self.записи[ключ] = {"путь": путь, "режим": режим, "blob": полный_объект(blob)}
        return self.записи[ключ]

    def прочитать(self, объект, путь):
        запись = self.запись(объект, путь)
        if запись["blob"] not in self.байты:
            self.байты[запись["blob"]] = self.выполнить("show", объект + ":" + путь)
        return self.байты[запись["blob"]]


def прочитать_рабочий_файл(корень, имя, путь):
    путь = Path(путь)
    требовать(путь.is_absolute() and путь == корень / (ПУТЬ_СООБЩЕНИЙ + имя), "Нужен полный назначенный путь файла checkout")
    try:
        for часть in (путь, *путь.parents):
            требовать(not часть.is_symlink(), "Символическая ссылка в пути принятого файла")
        сведения = путь.stat()
        требовать(stat.S_ISREG(сведения.st_mode), "Принятый файл должен быть обычным")
        режим = "100755" if сведения.st_mode & 0o111 else "100644"
        return путь.read_bytes(), режим
    except OSError as ошибка:
        raise Несовместимость("Недоступен полный принятый файл checkout") from ошибка


def проверить(корень, база, прежний, события, дерево, файлы):
    начало = perf_counter_ns()
    требовать(база == БАЗА_ПОСТАНОВКИ and прежний == ПРЕЖНИЙ_КОММИТ, "Не та первоначальная база или прежний принятый коммит")
    полный_объект(события)
    полный_объект(дерево)
    требовать(set(файлы) == set(ХЭШИ_ПРИНЯТЫХ), "Нужны все три прежних файла")
    читатель = ЧитательGit(корень)
    читатель.коммит(база)
    читатель.коммит(прежний)
    закреплённый = читатель.коммит(события)
    требовать(закреплённый["tree"] == дерево and закреплённый["родители"] == [база], "Дерево H или родители не совпали с [C]")
    читатель.выполнить("merge-base", "--is-ancestor", прежний, база)
    # Первое чтение потока выполняется через git show именно H. Одинаковый blob
    # входа C затем используется из кэша после отдельной проверки его Git-записи.
    поток = читатель.прочитать(события, ПУТЬ_СОБЫТИЙ + "поток.jsonl")
    свидетельство = читатель.прочитать(события, ПУТЬ_СОБЫТИЙ + "свидетельство.json")
    вход = читатель.прочитать(база, ПУТЬ_ВХОДА)
    принятые, рабочие, сведения = {}, {}, {}
    for имя, ожидаемый_хэш in ХЭШИ_ПРИНЯТЫХ.items():
        путь = ПУТЬ_СООБЩЕНИЙ + имя
        запись = читатель.запись(база, путь)
        требовать(запись == читатель.запись(прежний, путь), "Blob или режим прежнего файла изменился между принятым коммитом и C")
        принятые[имя] = читатель.прочитать(база, путь)
        требовать(хэш(принятые[имя]) == ожидаемый_хэш, "Не совпал согласованный SHA принятого файла")
        рабочие[имя] = прочитать_рабочий_файл(читатель.корень, имя, файлы[имя])
        сведения[имя] = запись | {"sha256": хэш(принятые[имя]), "байтов": len(принятые[имя])}
    исходники = {}
    for запись in прочитать_строки(вход):
        путь = запись["исходник"]["путь"]
        if путь not in исходники:
            исходники[путь] = читатель.прочитать(база, путь)
    после_чтения = perf_counter_ns()
    for имя in принятые:
        требовать(рабочие[имя] == (принятые[имя], сведения[имя]["режим"]), "Байты или режим прежнего файла checkout изменились: " + имя)
    итог_потока = сверить_поток(вход, поток, свидетельство)
    сравнения = сверить_записи(вход, рабочие["значимые-сообщения.jsonl"][0], рабочие["связи-происхождения.json"][0], исходники)
    for имя in принятые:
        требовать(прочитать_рабочий_файл(читатель.корень, имя, файлы[имя]) == рабочие[имя], "Принятый файл изменился во время сверки")
    конец = perf_counter_ns()
    return {"схема": "fum.проверка-совместимости-сообщений.1", "база": база, "прежний_коммит": прежний,
            "события": закреплённый, "файлы": сведения, "поток": итог_потока, "сравнения": сравнения,
            "чтения": {"коммитов": len(читатель.коммиты), "уникальных_blobs": len(читатель.байты), "вызовов_Git": читатель.вызовов},
            "профиль_наносекунды": {"чтение_Git": после_чтения - начало, "сверка": конец - после_чтения, "весь_проход": конец - начало}}


def сверить_закрепление(корень, ref, объект, дерево, origin):
    """Наблюдение живой публикации; не используется предметным проверяющим."""
    требовать(type(ref) is str and ref.startswith("refs/heads/codex/"), "Нужен полный согласованный ref")
    полный_объект(объект)
    полный_объект(дерево)
    требовать(origin == "https://github.com/fum-lab/fum.git", "Не согласованный origin")
    читатель = ЧитательGit(корень)
    читатель.выполнить("check-ref-format", ref)
    for параметры in (("remote", "get-url", "--all", "origin"), ("remote", "get-url", "--push", "--all", "origin")):
        требовать(читатель.выполнить(*параметры).decode().splitlines() == [origin], "Origin неоднозначен или изменился")
    требовать(читатель.выполнить("rev-parse", "--verify", ref).decode().strip() == объект, "Живой локальный ref сдвинулся")
    сведения = читатель.коммит(объект)
    требовать(сведения["tree"] == дерево and сведения["родители"] == [БАЗА_ПОСТАНОВКИ], "Не совпал закреплённый H")
    удалённый = читатель.выполнить("ls-remote", "--refs", "origin", ref).decode().splitlines()
    требовать(удалённый == [объект + "\t" + ref], "Удалённый ref отсутствует или сдвинулся")
    требовать(читатель.выполнить("rev-parse", "--verify", ref).decode().strip() == объект, "Локальный ref сдвинулся при наблюдении сети")
    return {"ref": ref, "OID": объект, "tree": дерево, "origin": origin, "удалённый_OID": объект,
            "локальная_повторная_сверка": True, "состояние": "точно опубликован при наблюдении",
            "граница": "отдельное наблюдение живого ref; не доказательство предметной совместимости"}

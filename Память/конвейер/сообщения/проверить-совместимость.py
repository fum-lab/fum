"""CLI предметной сверки; stdout не принимается повторно как доказательство."""

import argparse
import json
from pathlib import Path
from time import perf_counter_ns

from проверка_совместимости import Несовместимость, проверить, сверить_закрепление


def главная():
    разбор = argparse.ArgumentParser(description="Сверить принятые сообщения с точными Git-объектами пилота")
    for имя in ("корень", "база", "прежний-коммит", "события", "дерево-событий", "README", "сообщения", "происхождение"):
        разбор.add_argument("--" + имя, required=True)
    разбор.add_argument("--повторы", type=int, default=1)
    разбор.add_argument("--проверить-публикацию", action="store_true")
    разбор.add_argument("--ref")
    разбор.add_argument("--origin")
    параметры = vars(разбор.parse_args())
    if not 1 <= параметры["повторы"] <= 100:
        разбор.error("Число повторов должно быть от 1 до 100")
    if параметры["проверить_публикацию"] and (not параметры["ref"] or not параметры["origin"]):
        разбор.error("Для наблюдения публикации нужны --ref и --origin")
    файлы = {"README.md": Path(параметры["README"]), "значимые-сообщения.jsonl": Path(параметры["сообщения"]),
             "связи-происхождения.json": Path(параметры["происхождение"])}
    try:
        проходы, повторные = [], []
        результат = None
        for номер in range(параметры["повторы"]):
            начало = perf_counter_ns()
            результат = проверить(Path(параметры["корень"]), параметры["база"], параметры["прежний_коммит"],
                                  параметры["события"], параметры["дерево_событий"], файлы)
            длительность = perf_counter_ns() - начало
            проходы.append(результат["профиль_наносекунды"])
            if номер:
                повторные.append(длительность)
        результат["профиль"] = {
            "проходы": проходы, "повторная_сверка_наносекунды": повторные,
            "байтов_входа": 5790, "записей": 7,
            "граница": "чтение закреплённых Git-объектов и трёх рабочих файлов; затем сравнение семи записей и диапазонов; отдельные повторные полные проходы",
            "исключено": ["подготовка фикстуры", "сеть", "ожидание Desktop", "подготовка Журнала", "публикация"],
            "перекрытие": "весь_проход включает чтение_Git и сверку; повторная сверка включает собственные фазы; интервалы не суммируются повторно",
        }
        if параметры["проверить_публикацию"]:
            результат["наблюдение_публикации"] = сверить_закрепление(Path(параметры["корень"]), параметры["ref"],
                                                                  параметры["события"], параметры["дерево_событий"], параметры["origin"])
        print(json.dumps(результат, ensure_ascii=False, indent=2, sort_keys=True))
        return 0
    except Несовместимость as ошибка:
        print(json.dumps({"схема": "fum.проверка-совместимости-сообщений.1", "отказ": str(ошибка)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(главная())

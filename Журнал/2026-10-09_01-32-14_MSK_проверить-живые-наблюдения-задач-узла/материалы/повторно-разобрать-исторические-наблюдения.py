"""Адресное воспроизведение сохранённых ответов; внешний MCP не вызывается."""
import argparse
import hashlib
import json
from pathlib import Path
import statistics
import sys
import time
import tracemalloc


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    for имя in ("корень-репозитория", "доверие", "контейнер", "писатель", "читатель", "история", "выход", "исторический-выход"):
        разбор.add_argument("--" + имя, required=True, type=Path)
    параметры = vars(разбор.parse_args())
    корень = параметры["корень_репозитория"].resolve()
    sys.path.insert(0, str(корень / "Инструменты/fum-svyaznostj-rabochej-sessii/scripts"))
    import состояние_задач_узла as состояние
    доверие = json.loads(состояние.прочитать_файл(параметры["доверие"], предел=65536, приватный=True))
    история = json.loads(состояние.прочитать_файл(параметры["история"], предел=состояние.ПРЕДЕЛ, приватный=True))
    контейнер = состояние.КонтейнерПроцессов(корень_данных=параметры["контейнер"],
        писатель=параметры["писатель"], читатель=параметры["читатель"], корень_репозитория=корень)
    цикл = состояние.ЦиклНаблюдения(доверие, корень=корень, контейнер=контейнер, история=история)
    исход = цикл.итог()
    сверки = []
    for запись in цикл.история:
        объект = запись["объект"]
        начало = time.monotonic_ns()
        данные = контейнер.извлечь(объект["идентификатор"])
        цикл.проверить_объект(объект, данные)
        извлечение = time.monotonic_ns() - начало
        замеры = []
        tracemalloc.start()
        try:
            for номер in range(3):
                начало = time.monotonic_ns()
                проекция = состояние.проекция_ответа(данные, задача=запись["задача"], хост=запись["хост"])
                замеры.append(time.monotonic_ns() - начало)
            _, пик = tracemalloc.get_traced_memory()
        finally:
            tracemalloc.stop()
        запись["проекция"] = проекция
        запись["состояние"] = "исторический повторный разбор"
        запись["причина"] = None
        assert запись["свежее_в_этом_цикле"] is False
        сверки.append({"задача": запись["задача"], "объект": объект["идентификатор"],
            "байтов": len(данные), "sha256": hashlib.sha256(данные).hexdigest(),
            "извлечение_наносекунды": извлечение, "разбор_наносекунды": замеры,
            "медиана_разбора_наносекунды": statistics.median(замеры), "пик_python_байтов": пик,
            "элементы_по_типам": проекция["элементы_по_типам"], "допуск_эффекта": проекция["допуск_эффекта"]})
    новый = состояние.ЦиклНаблюдения(доверие, корень=корень, контейнер=контейнер, история=цикл.история).итог()
    assert новый["цикл"] != исход["цикл"]
    assert новый["наблюдения"] == исход["наблюдения"] == []
    assert новый["предпросмотр"] == исход["предпросмотр"]
    assert all(запись["свежее_в_этом_цикле"] is False for запись in новый["история"])
    assert новый["поколение_актуально"] and исход["поколение_актуально"]
    assert all(новый["профиль"][поле] == исход["профиль"][поле] == 0
        for поле in ("вызовов_читающего_адаптера", "mcp_наносекунды", "send", "create"))
    with параметры["исторический_выход"].open("xb") as поток:
        поток.write(состояние.кодировать(новый["история"]))
    результат = {"схема": "fum.историческая-сверка-служебных-типов.1", "ожидания": новый["поколение"],
        "циклы": [исход["цикл"], новый["цикл"]], "сверки": сверки, "исторических": len(новый["история"]),
        "все_исторические_несвежие": True, "предпросмотр_не_изменился": True,
        "поколение_актуально": True, "MCP": 0, "send": 0, "create": 0,
        "исходники_sha256": {str(путь.relative_to(корень)): hashlib.sha256(путь.read_bytes()).hexdigest()
            for путь in (Path(__file__).resolve(), Path(состояние.__file__).resolve())},
        "граница": "Один новый процесс; два контроллера без наблюдать; реальные Swift-reader и сохранённые прежние ответы. По три разбора уже извлечённых байтов с tracemalloc. Импорт, Git и извлечение вне таймера parser; холодный I/O, HTTP и память Swift неизвестны. Повторный разбор исторический, новые MCP-вызовы и рекомендации по истории отсутствуют."}
    with параметры["выход"].open("xb") as поток:
        поток.write(состояние.кодировать(результат))
    print(json.dumps({"исторических": результат["исторических"], "MCP": 0, "send": 0, "create": 0,
        "все_исторические_несвежие": True, "предпросмотр_не_изменился": True}, ensure_ascii=False))


if __name__ == "__main__":
    выполнить()

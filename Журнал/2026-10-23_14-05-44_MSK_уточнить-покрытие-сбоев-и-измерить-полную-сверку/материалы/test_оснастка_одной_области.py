        for рамка, роль in enumerate(['Git', 'разбор Git-дерева', 'построение принятого индекса'], 2):
            событие('начало', роль, рамка, 1); событие('конец', роль, рамка, 1)
        событие('конец', 'полная область', 1, None)
        return {'схема': 'fum.наблюдение-полного-доказательства.1',
            'полон': True, 'ошибки_наблюдения': [], 'события': события, 'событий': 8, 'рамок': 4}



def проверить_порядок(стадии):
    if type(стадии) is not list or any(type(имя) is not str for имя in стадии):
        raise ValueError('нужен явный список имён стадий')
    if tuple(стадии) != ПОРЯДОК:
        raise ValueError('неполная или переставленная последовательность восстановления')
    return tuple(стадии)


class ОснасткаОбласти(unittest.TestCase):
    def test_сбой_диагностики_не_подменяет_исходное_исключение(сам):
        дерево = ast.parse(путь.read_bytes())
        главная = next(у for у in дерево.body if isinstance(у, ast.FunctionDef) and у.name == 'главная')
        диагностика = [у for у in главная.body if isinstance(у, ast.Try)][1]
        исходная = LookupError('исходная операция')
        def снимок():
            raise ValueError('вторичная диагностика')
        область = {'снимок': снимок, 'исходное_исключение': (исходная, None)}
        with сам.assertRaises(LookupError) as исход:
            exec(compile(ast.Module(body=[диагностика], type_ignores=[]), str(путь), 'exec'), область)
        сам.assertIs(исход.exception, исходная)
        область['исходное_исключение'] = None
        with сам.assertRaises(ValueError):
            exec(compile(ast.Module(body=[диагностика], type_ignores=[]), str(путь), 'exec'), область)


    def test_снимок_учитывает_подготовленный_путь_режим_и_ветку(сам):
        # Выполняется точное тело вложенной функции, а не его копия.
        дерево = ast.parse(путь.read_bytes())
        главная = next(у for у in дерево.body if isinstance(у, ast.FunctionDef) and у.name == 'главная')
        снимок = next(у for у in главная.body if isinstance(у, ast.FunctionDef) and у.name == 'снимок')
        with tempfile.TemporaryDirectory() as каталог:
            корень = Path(каталог).resolve(); файл = корень/'подготовлен.py'
            файл.write_bytes(b'pass\n'); файл.chmod(0o600)
            индекс = корень/'индекс'; индекс.write_bytes(b'index')
            вызовы = []
            def гит(*аргументы):
                вызовы.append(аргументы)
                if аргументы == ('diff', '--cached', '--name-only', '-z'):
                    return 'подготовлен.py\0'.encode()
                if аргументы[:1] in (('diff',), ('ls-files',)):
                    return b''
                if аргументы[:2] == ('rev-parse', '--path-format=absolute'):
                    return str(индекс).encode()
                return {('status', '--porcelain=v1', '-z'): b'M  staged',
                    ('rev-parse', 'HEAD'): b'123', ('symbolic-ref', 'HEAD'): b'refs/heads/test'}[аргументы]
            область = dict(vars(оснастка), корень=корень, гит=гит,
                параметры={'разрешённые_цели': ['подготовлен.py']})
            exec(compile(ast.Module(body=[снимок], type_ignores=[]), str(путь), 'exec'), область)
            до = область['снимок'](); файл.chmod(0o700); после = область['снимок']()
            сам.assertNotEqual(до, после)
            сам.assertEqual(до['ref'], 'refs/heads/test')
            сам.assertIn('подготовлен.py', до['файлы'])

    def трасса(сам):
        события = []; порядок = 0
        def событие(вид, роль, рамка, родитель):
            nonlocal порядок
            порядок += 1
            события.append({'событие': вид, 'роль': роль, 'рамка': рамка,
                'родитель': родитель, 'порядок': порядок, 'монотонные_нс': порядок,
                'исход': 'успех'})

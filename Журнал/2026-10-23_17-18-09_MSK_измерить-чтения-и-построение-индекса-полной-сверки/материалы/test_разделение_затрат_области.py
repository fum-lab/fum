class Непрозрачный:
    def read_bytes(сам):
        raise AssertionError('повторное чтение')

    def __iter__(сам):
        raise AssertionError('повторный обход')


class РазделениеЗатрат(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        класс.м = загрузить()

    def test_чтение_считает_исходные_байты_и_признаки(self):
        данные = self.м.данные_чтения((Непрозрачный(),),
            {'материал': b'abc', 'ожидаемая': [1]}, (b'abc', Непрозрачный()))
        self.assertEqual(данные, {'байты': 3, 'с_материалом': True, 'с_ожидаемой': True})
        self.assertEqual(self.м.данные_чтения((Непрозрачный(),), {},
            (b'', '100644')), {'байты': 0, 'с_материалом': False, 'с_ожидаемой': False})

    def test_инвентарь_не_читает_возвращённые_пути(self):
        self.assertEqual(self.м.данные_инвентаря((Непрозрачный(),), {},
            {'а': Непрозрачный(), 'б': Непрозрачный()}), {'путей': 2})

    def test_разбор_не_сериализует_и_не_обходит_результат(self):
        self.assertEqual(self.м.данные_разбора_данных((b'{}',), {}, Непрозрачный()),
            {'тип_входа': 'bytes', 'входные_байты': 2, 'входные_символы': None,
             'тип_результата': 'Непрозрачный'})

    def test_кириллическая_строка_не_считается_сырыми_байтами(self):
        self.assertEqual(self.м.данные_разбора_данных(('{"ё":1}',), {}, {}),
            {'тип_входа': 'str', 'входные_байты': None, 'входные_символы': 7,
             'тип_результата': 'dict'})

    def test_индекс_не_хэширует_и_не_перечитывает_вход(self):
        self.assertEqual(self.м.данные_чистого_индекса(
            (Непрозрачный(), {'а': Непрозрачный(), 'б': Непрозрачный()}),
            {'ожидаемый_sha256': Непрозрачный()}, {'байты': b'abc', 'записей': 1}),
            {'входных_файлов': 2, 'записей': 1, 'индекс_байты': 3})

    def точки(self):
        def действие(*аргументы, **поля):
            raise AssertionError('создание списка не должно исполнять цель')
        область = SimpleNamespace(**{имя: действие for имя in
            ('проверить_область_записей', 'прочитать_разметку',
             'прочитать_обычный_файл', 'инвентарь_разметки')})
        журнал = SimpleNamespace(**{имя: действие for имя in
            ('_гит', '_разобрать_дерево_коммита', 'построить_принятый_индекс',
             '_разобрать_данные', 'точный_путь')}, индексы=SimpleNamespace(построить_индекс=действие))
        return self.м.точки_наблюдения(область, журнал)

    def test_регистрация_точных_тринадцати_маркеров_не_вызывает_цели(self):
        точки = self.точки()
        self.assertEqual(len(точки), 13)
        self.assertEqual(len({(id(м), имя) for м, имя, _, _ in точки}), 13)
        self.assertEqual({роль for _, _, роль, _ in точки}, {
            'Git', 'разбор Git-дерева', 'построение принятого индекса', 'полная область',
            'чтение Markdown', 'чтение обычного файла', 'инвентарь W',
            'чистый разбор JSON', 'чистое построение индекса',
            'точный путь', 'физический путь', 'SHA1', 'SHA256'})

    def трасса(self, роли):
        события = []
        def добавить(вид, рамка, роль, родитель):
            событие = {'событие': вид, 'рамка': рамка, 'роль': роль,
                'родитель': родитель, 'монотонные_нс': len(события),
                'порядок': len(события) + 1}
            if вид == 'конец':
                событие.update(исход='успех', данные=None)
            события.append(событие)
        добавить('начало', 1, 'полная область', None)
        for номер, роль in enumerate(роли, 2):
            добавить('начало', номер, роль, 1)
            добавить('конец', номер, роль, 1)
        добавить('конец', 1, 'полная область', None)
        return {'схема': 'fum.наблюдение-полного-доказательства.1',
            'полон': True, 'ошибки_наблюдения': [], 'события': события,
            'событий': len(события), 'рамок': 1 + len(роли)}

    def test_трасса_принимает_новые_роли_с_правильной_вложенностью(self):
        роли = [роль for _, _, роль, _ in self.точки() if роль != 'полная область']
        self.м.сверить_трассу(self.трасса(роли), успех=True)

    def test_трасса_отвергает_необъявленную_роль(self):
        with self.assertRaises(ValueError):
            self.м.сверить_трассу(self.трасса(['необъявленный вызов']), успех=False)


class ПерваяКоманда(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        путь = Path(__file__).with_name('команда_первой_проверки.py')
        описание = importlib.util.spec_from_file_location('первая_команда', путь)
        класс.м = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(класс.м)

    def test_схема_вставляется_до_разделителя_без_изменения_оригинала(self):
        команда = ['исполнитель', 'запустить', '--', 'тест', '--обычная-схема-профиля']
        self.assertEqual(self.м.подготовить(команда, схема='--приёмочные-раунды'),
            ['исполнитель', 'запустить', '--приёмочные-раунды', '--',
             'тест', '--обычная-схема-профиля'])
        self.assertEqual(команда, ['исполнитель', 'запустить', '--', 'тест',
            '--обычная-схема-профиля'])

    def test_уже_выбранная_схема_не_дублируется(self):
        команда = ['исполнитель', 'запустить', '--приёмочные-раунды', '--', 'тест']
        self.assertEqual(self.м.подготовить(команда, схема='--приёмочные-раунды'), команда)

    def test_конфликт_и_неполная_команда_отвергаются(self):
        случаи = [(['исполнитель', '--приёмочные-раунды', '--обычная-схема-профиля', '--'],
                    '--приёмочные-раунды'),
                  (['исполнитель', '--обычная-схема-профиля', '--'], '--приёмочные-раунды'),
                  (['исполнитель'], '--приёмочные-раунды'),
                  (['исполнитель', '--'], 'неизвестная схема')]
        for команда, схема in случаи:
            with self.subTest(команда=команда, схема=схема), self.assertRaises(ValueError):
                self.м.подготовить(команда, схема=схема)


class ПутиИХэши(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        класс.м = загрузить()
        путь = Path(__file__).parents[3] / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/наблюдение_полного_доказательства.py'
        описание = importlib.util.spec_from_file_location('наблюдение_дополнительных_точек', путь)
        модуль = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(модуль)
        класс.Наблюдение = модуль.Наблюдение

    def test_добавлены_только_четыре_нужные_точки(self):
        область = SimpleNamespace()
        журнал = SimpleNamespace(индексы=SimpleNamespace())
        точки = self.м.точки_наблюдения(область, журнал)
        новые = {роль: (объект, имя) for объект, имя, роль, _ in точки[9:]}
        self.assertEqual(новые, {'точный путь': (журнал, 'точный_путь'),
            'физический путь': (Path, 'resolve'), 'SHA1': (hashlib, 'sha1'),
            'SHA256': (hashlib, 'sha256')})

    def test_метаданные_путей_не_читают_пути(self):
        путь = Непрозрачный()
        self.assertEqual(self.м.данные_пути((путь, путь),
            {'индекс': путь, 'существует': True}, путь),
            {'с_индексом': True, 'существует': True})
        self.assertEqual(self.м.данные_resolve((путь, True), {}, путь), {'strict': True})
        self.assertEqual(self.м.данные_resolve((путь,), {'strict': False}, путь), {'strict': False})

    def test_resolve_сохраняет_strict_отказ_и_восстановление(self):
        наблюдение = self.Наблюдение()
        исходный = Path.resolve
        with tempfile.TemporaryDirectory() as каталог:
            отсутствующий = Path(каталог) / 'нет'
            ожидаемый = исходный(отсутствующий, strict=False)
            with patch.object(Path, 'resolve', наблюдение.обернуть(
                    'физический путь', исходный, self.м.данные_resolve)):
                with self.assertRaises(FileNotFoundError):
                    отсутствующий.resolve(strict=True)
                self.assertEqual(отсутствующий.resolve(strict=False), ожидаемый)
        self.assertIs(Path.resolve, исходный)
        трасса = наблюдение.срез()
        self.assertEqual(трасса['рамок'], 2)
        self.assertEqual([с['исход'] for с in трасса['события'] if с['событие'] == 'конец'],
            ['отказ', 'успех'])

    def test_хэш_сохраняет_объект_update_и_диагностику_без_рекурсии(self):
        наблюдение = self.Наблюдение()
        исходный_sha256 = hashlib.sha256
        исходный_sha1 = hashlib.sha1
        объект = исходный_sha1('а'.encode())
        def создать(*аргументы, **поля):
            self.assertEqual(аргументы, ('а'.encode(),))
            self.assertEqual(поля, {'usedforsecurity': False})
            return объект
        def сведения(аргументы, поля, результат):
            # SHA из callback должен пройти без наблюдения самой диагностики.
            hashlib.sha256('диагностика'.encode()).hexdigest()
            return self.м.данные_хэша(аргументы, поля, результат)
        with patch.object(hashlib, 'sha256', наблюдение.обернуть(
                'SHA256', исходный_sha256, self.м.данные_хэша)), patch.object(
                hashlib, 'sha1', наблюдение.обернуть('SHA1', создать, сведения)):
            результат = hashlib.sha1('а'.encode(), usedforsecurity=False)
            self.assertIs(результат, объект)
            результат.update('б'.encode())
            self.assertEqual(результат.hexdigest(), исходный_sha1('аб'.encode()).hexdigest())
        self.assertIs(hashlib.sha256, исходный_sha256)
        self.assertIs(hashlib.sha1, исходный_sha1)
        трасса = наблюдение.срез()
        self.assertEqual(трасса['рамок'], 1)
        self.assertEqual(трасса['ошибки_наблюдения'], [])
        self.assertEqual(трасса['события'][-1]['данные'], {'входные_байты': 2})


class ВыходыНаблюдения(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        путь = Path(__file__).with_name('команда_первой_проверки.py')
        описание = importlib.util.spec_from_file_location('выходы_первой_команды', путь)
        класс.м = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(класс.м)

    def test_артефакт_не_совпадает_с_метаданными_наблюдателя(self):
        каталог = Path(__file__).parent
        with self.assertRaises(ValueError):
            self.м.сверить_выходы(каталог, 'процесс', [каталог/'процесс.json'])

    def test_все_четыре_служебных_выхода_зарезервированы(self):
        каталог = Path(__file__).parent
        for суффикс in ('.process', '.json', '.stdout', '.stderr'):
            with self.subTest(суффикс=суффикс), self.assertRaises(ValueError):
                self.м.сверить_выходы(каталог, 'процесс', [каталог/('процесс'+суффикс)])

    def test_раздельные_артефакты_разрешены_а_дубли_отвергаются(self):
        каталог = Path(__file__).parent
        self.м.сверить_выходы(каталог, 'процесс', [каталог/'результат.json'])
        with self.assertRaises(ValueError):
            self.м.сверить_выходы(каталог, 'процесс',
                [каталог/'результат.json', каталог/'результат.json'])



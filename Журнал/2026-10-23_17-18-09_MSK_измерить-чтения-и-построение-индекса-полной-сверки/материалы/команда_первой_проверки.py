"""Формирование первой команды отчёта отдельно от её исполнения."""
from pathlib import Path


def подготовить(команда, *, схема):
    схемы = {'--приёмочные-раунды', '--обычная-схема-профиля'}
    if (type(команда) is not list or not all(type(ч) is str for ч in команда)
            or схема not in схемы or '--' not in команда):
        raise ValueError('нужны команда, разделитель и явная схема первой проверки')
    граница = команда.index('--')
    выбранные = [ч for ч in команда[:граница] if ч in схемы]
    if выбранные and выбранные != [схема]:
        raise ValueError('конфликт схем первой проверки')
    результат = list(команда)
    if not выбранные:
        результат.insert(граница, схема)
    return результат


def сверить_выходы(каталог, префикс, выходы):
    каталог = Path(каталог)
    if (not каталог.is_absolute() or каталог.resolve() != каталог
            or type(префикс) is not str or not префикс
            or Path(префикс).name != префикс or префикс in {'.', '..'}):
        raise ValueError('нужны физический каталог и простое имя процесса')
    служебные = {каталог/(префикс+с) for с in ('.process', '.json', '.stdout', '.stderr')}
    пути = [Path(п).resolve() for п in выходы]
    if len(пути) != len(set(пути)) or служебные.intersection(пути):
        raise ValueError('артефакт совпал с другим выходом или данными наблюдателя')

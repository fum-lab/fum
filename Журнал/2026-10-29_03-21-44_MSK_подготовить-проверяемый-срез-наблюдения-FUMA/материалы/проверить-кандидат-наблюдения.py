#!/usr/bin/env python3
import argparse
import hashlib
import json
import os
import subprocess
from pathlib import Path


ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ = {
    "идентификатор",
    "framework_или_API",
    "наблюдаемый_сигнал",
    "состав",
    "намерение",
    "ответ",
    "долговечное_воспроизведение",
    "происхождение",
    "разрешения_и_эффекты",
    "приватность",
    "проверки",
    "состояние",
    "граница",
}


def git(корень: Path, *аргументы: str, байты: bool = False):
    результат = subprocess.run(
        ["git", "-C", str(корень), *аргументы],
        check=True,
        stdout=subprocess.PIPE,
        text=not байты,
    )
    return результат.stdout


def разобрать_аргументы():
    разбор = argparse.ArgumentParser()
    разбор.add_argument("--корень", type=Path, required=True)
    разбор.add_argument("--ожидаемый-head", required=True)
    return разбор.parse_args()


def main() -> int:
    аргументы = разобрать_аргументы()
    корень = аргументы.корень.resolve()
    путь = корень / "Планирование/задачи/01a07d3d-d376-7ad2-aafc-67e4c25a67eb/результаты/приёмка-наблюдения.json"
    данные = путь.read_bytes()
    документ = json.loads(данные)
    канонические = (json.dumps(документ, ensure_ascii=False, indent=2) + "\n").encode()
    assert данные == канонические
    assert документ["схема"] == "fum.кандидат-приёмки-наблюдения.1"
    assert документ["задача"] == "01a07d3d-d376-7ad2-aafc-67e4c25a67eb"
    assert документ["работа"] == "FUMA-НАБЛЮДЕНИЕ-ЭТАП"
    assert документ["состояние"] == "контрольная-точка"
    assert документ["исходный_HEAD"] == аргументы.ожидаемый_head
    assert git(корень, "rev-parse", "HEAD").strip() == аргументы.ожидаемый_head
    assert git(корень, "rev-parse", "HEAD^{tree}").strip() == документ["исходное_дерево"]

    состояния = set(документ["критерий_полноты"]["допустимые_состояния"])
    каналы = документ["каналы"]
    идентификаторы = [канал["идентификатор"] for канал in каналы]
    assert len(каналы) == 7
    assert len(идентификаторы) == len(set(идентификаторы))
    for канал in каналы:
        assert ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ <= set(канал)
        assert канал["состояние"] in состояния

    assert документ["решение"]["финальная_приёмка"] is False
    assert документ["решение"]["регистрация_в_приёмках_этапов"] is False
    assert документ["каналы"][0]["идентификатор"] == "ax-trust-availability"
    assert документ["каналы"][0]["состояние"] == "кандидат-на-принятие"
    assert {канал["идентификатор"] for канал in каналы if канал["состояние"] == "требует-исправления"} == {
        "filesystem",
        "git-readonly",
    }

    дерево_пакета = git(
        корень,
        "rev-parse",
        "HEAD:Приложения/FUMA/Packages/НаблюдениеДоступности",
    ).strip()
    assert дерево_пакета == документ["каналы"][0]["состав"]["дерево_пакета"]

    индекс = {канал["идентификатор"]: канал for канал in каналы}
    проверяемые_пути = [
        ("ax-ui-snapshot", индекс["ax-ui-snapshot"]["состав"]),
        ("input-events", индекс["input-events"]["состав"]),
        ("attention-loop", индекс["attention-loop"]["состав"]),
        ("camera-gaze-face", индекс["camera-gaze-face"]["состав"]),
        ("долговечный-писатель", документ["долговечный_писатель"]),
    ]
    for _, состав in проверяемые_пути:
        путь_файла = состав.get("путь", состав.get("manifest"))
        абсолютный = корень / путь_файла
        assert абсолютный.is_file() and not абсолютный.is_symlink()
        строка = git(корень, "ls-tree", "HEAD", "--", путь_файла).strip()
        режим, вид, blob, _ = строка.split(maxsplit=3)
        assert вид == "blob"
        assert режим == состав["режим"]
        assert blob == состав["blob"]
        assert hashlib.sha256(абсолютный.read_bytes()).hexdigest() == состав["sha256"]

    for oid in (
        "f8fce0f1a01284f3faf5baad1c32361e0f4234d3",
        "5bc964ad765628bded5c90e99de3cf24a5ab3ac2",
        "371ceea4e06ddded8312890160a013e2941cd7cf",
        "c566b20aa8734f73cdaa82e9cdfcb27b2d6daf2c",
        "2492936ac563f76e7eeaf1027a8cd9e19ccedafa",
    ):
        assert git(корень, "cat-file", "-t", oid).strip() == "commit"

    каталог = корень / документ["трасса_проверок"]["каталог"]
    квитанции = {}
    текущий_запуск = os.environ.get("FUM_CHECK_RUN_ID")
    for файл in каталог.glob("*.json"):
        квитанция = json.loads(файл.read_bytes())
        if квитанция["идентификатор"] == текущий_запуск:
            assert квитанция["состояние"] == "выполняется"
            continue
        assert квитанция["схема"] == "fum.test-run.v3"
        assert квитанция["состояние"] == "завершён"
        квитанции[квитанция["идентификатор"]] = квитанция
    заявленные = set(документ["трасса_проверок"]["успешные"])
    заявленные.update(запись["идентификатор"] for запись in документ["трасса_проверок"]["неуспешные"])
    assert заявленные <= set(квитанции)
    assert all(квитанции[идентификатор]["статус"] == "успешно" for идентификатор in документ["трасса_проверок"]["успешные"])
    отказ = документ["трасса_проверок"]["неуспешные"][0]
    assert квитанции[отказ["идентификатор"]]["статус"] == "неуспешно"
    диагностика = квитанции[отказ["диагностика"]]
    assert диагностика["профиль_проверки"]["идентификатор_отказа"] == отказ["идентификатор"]
    assert квитанции[отказ["исправленный_повтор"]]["статус"] == "успешно"

    реестр = json.loads((корень / "Планирование/задачи/01a07d3d-d376-7ad2-aafc-67e4c25a67eb/обязательства.json").read_bytes())
    assert all(запись["работа"] != "FUMA-НАБЛЮДЕНИЕ-ЭТАП" for запись in реестр["приёмки_этапов"])

    print(json.dumps({
        "схема": документ["схема"],
        "каналов": len(каналы),
        "квитанций_в_кандидате": len(заявленные),
        "sha256": hashlib.sha256(данные).hexdigest(),
        "финальная_приёмка": False,
    }, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

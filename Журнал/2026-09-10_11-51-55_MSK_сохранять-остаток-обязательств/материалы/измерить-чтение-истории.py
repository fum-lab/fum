"""Парное измерение полного чтения истории и выбора остатка на одном HEAD."""
import importlib.util
import json
import statistics
import subprocess
import sys
import time
import tracemalloc
from pathlib import Path
from unittest.mock import patch

корень = Path(__file__).resolve().parents[3]
материалы = Path(__file__).resolve().parent
sys.path.insert(0, str(корень / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts'))
import история_пути_гита as история
import обязательства_задачи as обязательства

спецификация = importlib.util.spec_from_file_location('исходная_история', материалы / 'история-до-пакетного-чтения.py')
исходная = importlib.util.module_from_spec(спецификация)
спецификация.loader.exec_module(исходная)
ожидаемый = 'ef6b936be7ac4ac518e0c5b5f5792263a686fab7'
реестр = корень / 'Планирование/задачи/01a07d3d-d376-7ad2-aafc-67e4c25a67eb/обязательства.json'
вход = реестр.read_bytes()
запустить = subprocess.run
эталон = None
эталон_истории = None
измерения = []


def измерить(модуль, вариант, номер):
    global эталон, эталон_истории
    счётчики = {'процессов_git': 0, 'байтов_stdout_git': 0}

    def считать(*аргументы, **параметры):
        результат = запустить(*аргументы, **параметры)
        счётчики['процессов_git'] += 1
        счётчики['байтов_stdout_git'] += len(результат.stdout or b'')
        return результат

    with patch.object(обязательства, 'прочитать_историю', модуль.прочитать_историю), patch.object(обязательства, 'состояния_пути', модуль.состояния_пути), patch('subprocess.run', считать):
        tracemalloc.start()
        начало = time.perf_counter_ns()
        начало_процессорного_времени = time.process_time_ns()
        проверка = обязательства.ПроверкаОбязательств(корень, обязательства.ГРАНИЦА_ЗАДАЧИ)
        результат = проверка.остаток(вход)
        процессорное_время = time.process_time_ns() - начало_процессорного_времени
        длительность = time.perf_counter_ns() - начало
        _, пик = tracemalloc.get_traced_memory()
        tracemalloc.stop()
    assert результат['вершина'] == ожидаемый
    if эталон is None:
        эталон, эталон_истории = результат, проверка.история
    assert результат == эталон and проверка.история == эталон_истории
    измерения.append({'вариант': вариант, 'повтор': номер, 'длительность_мс': длительность / 1e6,
                       'процессорное_время_питона_мс': процессорное_время / 1e6, 'пик_памяти_питона_байтов': пик, **счётчики})
    print(вариант, номер, round(длительность / 1e6, 3), 'мс', flush=True)


for номер in range(1, 4):
    варианты = [(исходная, 'до'), (история, 'после')]
    for модуль, вариант in варианты if номер % 2 else reversed(варианты):
        измерить(модуль, вариант, номер)
assert реестр.read_bytes() == вход
сводка = {}
for вариант in ['до', 'после']:
    строки = [строка for строка in измерения if строка['вариант'] == вариант]
    сводка[вариант] = {ключ: statistics.median(строка[ключ] for строка in строки)
                       for ключ in ['длительность_мс', 'процессорное_время_питона_мс', 'пик_памяти_питона_байтов', 'процессов_git', 'байтов_stdout_git']}
вывод = {'схема': 'fum.профиль-чтения-истории.1', 'коммит': ожидаемый,
         'sha256_реестра': обязательства.хэш(вход),
         'sha256_исходника_до': обязательства.хэш(Path(исходная.__file__).read_bytes()),
         'sha256_исходника_после': обязательства.хэш(Path(история.__file__).read_bytes()),
         'коммитов': len(эталон_истории['родители']),
         'приёмок': len(эталон['подтверждённые_этапы']),
         'все_версии_и_родители_совпали': True, 'остатки_совпали': True,
         'граница': 'Вызов Python API после импорта: полная достижимая история и кандидат реестра без приёмок. Три чередующиеся пары; прогретость файлового кэша не контролируется. CPU и память только Python, без дочернего Git; tracemalloc включён в wall. Это не холодный запуск CLI и не профиль будущего большого реестра.',
         'медианы': сводка, 'измерения': измерения, 'остаток': эталон}
(материалы / 'профиль-сравнения.json').write_bytes(обязательства.канонические_байты(вывод))
print(json.dumps(сводка, ensure_ascii=False, indent=2))

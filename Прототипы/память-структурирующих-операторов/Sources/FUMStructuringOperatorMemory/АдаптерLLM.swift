/// Чистое формирование намерения. Выполнение HTTP принадлежит actor.
public enum ВызовLLM {
  public static func сформировать(_ запрос: ЗапросLLM) throws -> НамерениеLLM {
    let строки = [запрос.идентификатор, запрос.запрошеннаяМодель, запрос.секрет.идентификатор]
    guard
      строки.allSatisfy({
        !$0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
          && $0.utf8.count <= 512
          && !$0.unicodeScalars.contains(where: CharacterSet.controlCharacters.contains)
      }), !запрос.сообщения.isEmpty, запрос.сообщения.count <= 128,
      (1...1_000_000).contains(запрос.пределТокенов),
      (1...16_777_216).contains(запрос.пределБайтовОтвета),
      (запрос.система?.utf8.count ?? 0) <= 262_144,
      запрос.сообщения.allSatisfy({ !$0.текст.isEmpty && $0.текст.utf8.count <= 262_144 }),
      запрос.сообщения.reduce(0, { $0 + $1.текст.utf8.count }) <= 1_048_576
    else { throw ОшибкаLLM(.неверныйЗапрос, "Неверные поля или пределы запроса LLM") }
    let запросHTTP = try кодекLLM(запрос.поставщик).подготовить(запрос)
    let хэш = sha256Digest(
      try canonicalJSONData(ОсноваНамеренияLLM(запрос: запрос, запросHTTP: запросHTTP)))
    return НамерениеLLM(запрос: запрос, запросHTTP: запросHTTP, хэш: хэш)
  }

  public static func проверить(_ намерение: НамерениеLLM) throws {
    guard try сформировать(намерение.запрос) == намерение else {
      throw ОшибкаLLM(.протокол, "Намерение LLM изменено после подготовки")
    }
  }
}

private struct ОсноваНамеренияLLM: Codable, Sendable {
  let запрос: ЗапросLLM
  let запросHTTP: HTTPЗапросLLM
}

extension AutomationExecutor {
  /// Чистый оператор системы: возвращает значение намерения, не выполняет HTTP.
  public static func намерениеВызоваLLM(_ запрос: ЗапросLLM) throws -> НамерениеLLM {
    try ВызовLLM.сформировать(запрос)
  }
}

private func предложенияLLM(
  _ ответ: ОтветПоставщикаLLM, намерение: НамерениеLLM
) throws -> RecordedLLMEnvelope? {
  guard намерение.запрос.форматОтвета == .предложения else { return nil }
  let данные = Data(ответ.текст.utf8)
  guard данные.count <= 262_144 else {
    throw ОшибкаLLM(.пределРесурсов, "Превышен предел JSON предложений")
  }
  do {
    let декодер = JSONDecoder()
    декодер.keyDecodingStrategy = .convertFromSnakeCase
    let профили = try декодер.decode([OperatorProfile].self, from: данные)
    let подсказка = String(decoding: намерение.запросHTTP.тело, as: UTF8.self)
    let конверт = RecordedLLMEnvelope(
      schemaVersion: 1, adapterId: "fum.адаптер-llm.\(намерение.запрос.поставщик.rawValue)",
      model: ответ.наблюдаемаяМодель ?? намерение.запрос.запрошеннаяМодель,
      promptText: подсказка, promptHash: sha256Digest(намерение.запросHTTP.тело),
      responseHash: sha256Digest(try canonicalJSONData(профили)), proposals: профили)
    // Прежний responseHash по-прежнему относится к каноническим предложениям.
    return try RecordedLLMProposalAdapter.decode(data: canonicalJSONData(конверт))
  } catch {
    throw ОшибкаLLM(.неверныйJSON, "JSON предложений не прошёл прежний закрытый адаптер")
  }
}

private struct СборкаОтветаLLM: Sendable {
  let намерение: НамерениеLLM
  var метаданные: МетаданныеHTTPОтветаLLM?
  var байты = Data()
  var события: [СобытиеLLM] = []
  var разбор: РазборSSELLM
  var декодер: ДекодерПотокаLLM
  var перваяОшибка: ОшибкаLLM?
  var отклонениеПриёма: ОтклонениеПриёмаLLM?

  init(_ намерение: НамерениеLLM) {
    self.намерение = намерение
    self.разбор = РазборSSELLM(
      пределБайтовРамки: min(1_048_576, намерение.запрос.пределБайтовОтвета))
    self.декодер = ДекодерПотокаLLM(поставщик: намерение.запрос.поставщик)
  }

  var потоковыйОтвет: Bool {
    метаданные?.заголовки.contains {
      $0.key.lowercased() == "content-type" && $0.value.lowercased().contains("text/event-stream")
    } == true
  }

  mutating func принять(_ часть: ЧастьHTTPОтветаLLM) throws {
    if let перваяОшибка { throw перваяОшибка }
    do {
      switch часть {
      case .заголовки(let заголовки):
        guard метаданные == nil, байты.isEmpty, (100...599).contains(заголовки.статус) else {
          отклонениеПриёма = .заголовки(граница: байты.count, метаданные: заголовки)
          throw ОшибкаLLM(.протокол, "Повторные или поздние HTTP-заголовки")
        }
        метаданные = заголовки
      case .данные(let новые):
        guard метаданные != nil else {
          отклонениеПриёма = .данныеДоЗаголовков(наблюдалось: новые.count)
          throw ОшибкаLLM(.протокол, "Данные HTTP получены до заголовков")
        }
        let граница = байты.count
        let остаток = намерение.запрос.пределБайтовОтвета - граница
        let префикс = Data(новые.prefix(остаток))
        байты.append(префикс)
        try принятьПоток(префикс)
        guard новые.count <= остаток else {
          отклонениеПриёма = .пределОтвета(
            граница: граница, наблюдалось: новые.count, сохранено: префикс.count)
          throw ОшибкаLLM(.пределРесурсов, "Превышен предел байтов HTTP-ответа")
        }
      }
    } catch let ошибка as ОшибкаLLM {
      перваяОшибка = ошибка
      throw ошибка
    }
  }

  private mutating func принятьПоток(_ новые: Data) throws {
    if потоковыйОтвет, метаданные?.статус == 200 {
      for кадр in try разбор.принять(новые) { события += try декодер.принять(кадр) }
      // Сначала сохраняются завершённые кадры, затем наблюдается отложенный отказ.
      for кадр in try разбор.принять(Data()) { события += try декодер.принять(кадр) }
    }
  }

  mutating func восстановитьОтклонение(_ наблюдение: ОтклонениеПриёмаLLM) throws {
    guard перваяОшибка == nil else {
      throw ОшибкаLLM(.протокол, "RAW содержит более ранний отказ приёма")
    }
    switch наблюдение {
    case .пределОтвета(let граница, let наблюдалось, let сохранено):
      let предел = намерение.запрос.пределБайтовОтвета
      guard метаданные != nil, байты.count == предел,
        граница >= 0, граница <= предел, сохранено == предел - граница,
        наблюдалось > сохранено
      else { throw ОшибкаLLM(.протокол, "Неверное наблюдение усечения HTTP body") }
      отклонениеПриёма = наблюдение
      перваяОшибка = .init(.пределРесурсов, "Превышен предел байтов HTTP-ответа")
    case .заголовки(let граница, let заголовки):
      guard граница == байты.count,
        метаданные != nil || !байты.isEmpty || !(100...599).contains(заголовки.статус)
      else { throw ОшибкаLLM(.протокол, "Неверное наблюдение отклонённых заголовков") }
      do { try принять(.заголовки(заголовки)) } catch let ошибка as ОшибкаLLM {
        guard отклонениеПриёма == наблюдение else { throw ошибка }
      }
    case .данныеДоЗаголовков(let наблюдалось):
      guard метаданные == nil, байты.isEmpty, наблюдалось >= 0 else {
        throw ОшибкаLLM(.протокол, "Неверное наблюдение данных до заголовков")
      }
      отклонениеПриёма = наблюдение
      перваяОшибка = .init(.протокол, "Данные HTTP получены до заголовков")
    }
  }

  mutating func закончить(
    внешняяОшибка: ОшибкаLLM? = nil, отправлялся: Bool = true
  ) -> ЗаписьВызоваLLM {
    var ошибка = перваяОшибка ?? внешняяОшибка
    var ответ: ОтветПоставщикаLLM? = декодер.частичныйОтвет
    var предложения: RecordedLLMEnvelope?
    var исход: ИсходОтправкиLLM = отправлялся ? .неизвестен : .неОтправлялся
    if ошибка == nil {
      do {
        guard let метаданные else {
          throw ОшибкаLLM(.протокол, "Транспорт завершился без HTTP-заголовков")
        }
        guard (200...299).contains(метаданные.статус) else {
          исход = .ответПолучен
          let отказ = try? кодекLLM(намерение.запрос.поставщик).разобрать(байты)
          ответ = отказ
          throw ОшибкаLLM(
            .отказHTTP, "Поставщик вернул HTTP \(метаданные.статус)",
            кодПоставщика: отказ?.ошибка?.кодПоставщика, нативныеДанные: байты)
        }
        if потоковыйОтвет {
          for кадр in try разбор.завершить() { события += try декодер.принять(кадр) }
          ответ = try декодер.завершить()
        } else {
          ответ = try кодекLLM(намерение.запрос.поставщик).разобрать(байты)
          if намерение.запрос.поток, ответ?.ошибка == nil {
            throw ОшибкаLLM(.протокол, "Вместо запрошенного SSE получен обычный ответ")
          }
        }
        исход = .ответПолучен
        guard let полученный = ответ else {
          throw ОшибкаLLM(.протокол, "Отсутствует разобранный ответ")
        }
        if let отказ = полученный.ошибка { throw отказ }
        guard полученный.завершение == .завершено else {
          throw ОшибкаLLM(.неполныйОтвет, "Нативный ответ поставщика не завершён успешно")
        }
        предложения = try предложенияLLM(полученный, намерение: намерение)
      } catch let отказ as ОшибкаLLM {
        ошибка = отказ
      } catch {
        // Непроверенный localizedDescription не сохраняется: он может содержать секрет.
        ошибка = ОшибкаLLM(.протокол, "Не удалось разобрать ответ поставщика")
      }
    }
    if внешняяОшибка != nil { исход = отправлялся ? .неизвестен : .неОтправлялся }
    return ЗаписьВызоваLLM(
      намерение: намерение, метаданные: метаданные, сырыеБайтыОтвета: байты,
      хэшСырогоОтвета: sha256Digest(байты), события: события, ответ: ответ,
      ошибка: ошибка, ошибкаТранспорта: перваяОшибка == nil ? внешняяОшибка : nil,
      отклонениеПриёма: отклонениеПриёма, исходОтправки: исход, предложения: предложения)
  }
}

private actor ПриёмОтветаLLM {
  var сборка: СборкаОтветаLLM
  init(_ намерение: НамерениеLLM) { сборка = СборкаОтветаLLM(намерение) }
  func принять(_ часть: ЧастьHTTPОтветаLLM) throws { try сборка.принять(часть) }
  func закончить(_ ошибка: ОшибкаLLM?) -> ЗаписьВызоваLLM {
    сборка.закончить(внешняяОшибка: ошибка)
  }
}

public actor ИсполнительLLM {
  private let транспорт: any ТранспортLLM
  private var записи: [String: ЗаписьВызоваLLM] = [:]
  private var активные: [String: НамерениеLLM] = [:]
  private let пределЗаписей = 32
  private let пределАктивных = 2
  public init(транспорт: any ТранспортLLM) { self.транспорт = транспорт }

  public func исполнить(_ намерение: НамерениеLLM) async throws -> ЗаписьВызоваLLM {
    let идентификатор = намерение.запрос.идентификатор
    if let запись = записи[идентификатор] {
      guard запись.намерение == намерение else {
        throw ОшибкаLLM(.конфликтИдентификатора, "Идентификатор уже принадлежит другому намерению")
      }
      return запись
    }
    guard активные[идентификатор] == nil else {
      throw ОшибкаLLM(.конфликтИдентификатора, "Вызов с этим идентификатором уже исполняется")
    }
    try ВызовLLM.проверить(намерение)
    guard записи.count + активные.count < пределЗаписей, активные.count < пределАктивных else {
      throw ОшибкаLLM(.пределРесурсов, "Исчерпан конечный предел вызовов исполнителя")
    }
    if Task.isCancelled {
      var сборка = СборкаОтветаLLM(намерение)
      let запись = сборка.закончить(
        внешняяОшибка: .init(.отмена, "Отмена до отправки"), отправлялся: false)
      записи[идентификатор] = запись
      return запись
    }
    активные[идентификатор] = намерение
    defer { активные.removeValue(forKey: идентификатор) }
    let приём = ПриёмОтветаLLM(намерение)
    var ошибка: ОшибкаLLM?
    do {
      // Единственная отправка. В этом actor нет цикла retry или переподключения SSE.
      try await транспорт.отправить(намерение.запросHTTP) { часть in
        try await приём.принять(часть)
      }
    } catch is CancellationError {
      ошибка = ОшибкаLLM(.отмена, "Отмена после начала отправки")
    } catch let отказ as ОшибкаLLM {
      ошибка = отказ
    } catch {
      ошибка = ОшибкаLLM(.транспорт, "Транспорт завершился с неизвестным удалённым исходом")
    }
    let запись = await приём.закончить(ошибка)
    записи[идентификатор] = запись
    return запись
  }

  public func восстановить(_ запись: ЗаписьВызоваLLM) throws -> ЗаписьВызоваLLM {
    try ВызовLLM.проверить(запись.намерение)
    guard запись.хэшСырогоОтвета == sha256Digest(запись.сырыеБайтыОтвета) else {
      throw ОшибкаLLM(.протокол, "Изменены сохранённые байты ответа")
    }
    if запись.исходОтправки == .неОтправлялся {
      let отменаДоОтправки = ОшибкаLLM(.отмена, "Отмена до отправки")
      guard запись.метаданные == nil, запись.сырыеБайтыОтвета.isEmpty,
        запись.события.isEmpty, запись.ответ == nil, запись.предложения == nil,
        запись.отклонениеПриёма == nil, запись.ошибка == отменаДоОтправки,
        запись.ошибкаТранспорта == отменаДоОтправки
      else { throw ОшибкаLLM(.протокол, "Отсутствие отправки противоречит наблюдениям") }
    }
    var сборка = СборкаОтветаLLM(запись.намерение)
    do {
      if let метаданные = запись.метаданные { try сборка.принять(.заголовки(метаданные)) }
      if !запись.сырыеБайтыОтвета.isEmpty { try сборка.принять(.данные(запись.сырыеБайтыОтвета)) }
    } catch let ошибка as ОшибкаLLM {
      guard запись.ошибка?.вид == ошибка.вид else { throw ошибка }
    }
    if let отклонение = запись.отклонениеПриёма {
      try сборка.восстановитьОтклонение(отклонение)
    }
    // Транспортный отказ — сохранённое наблюдение, а не заново произведённый эффект.
    let проверенная = сборка.закончить(
      внешняяОшибка: запись.ошибкаТранспорта,
      отправлялся: запись.исходОтправки != .неОтправлялся)
    guard проверенная == запись else {
      throw ОшибкаLLM(.протокол, "Сохранённый результат не соответствует его RAW")
    }
    let идентификатор = запись.намерение.запрос.идентификатор
    guard активные[идентификатор] == nil,
      записи[идентификатор] == nil || записи[идентификатор] == запись,
      записи[идентификатор] != nil || записи.count + активные.count < пределЗаписей
    else {
      throw ОшибкаLLM(.конфликтИдентификатора, "Восстановление пересекает существующий вызов")
    }
    записи[идентификатор] = запись
    return запись
  }
}

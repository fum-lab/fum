import Foundation

/// Конечный чистый граф с явными ссылками только на предшествующие узлы.
public struct ГрафJSON: Equatable, Sendable {
  let узел: УзелОпределения

  init(_ узел: УзелОпределения) throws {
    self.узел = узел
    try проверить()
  }

  func проверить() throws {
    let поля = try узел.объект(["схема", "числа", "переменные", "результат"])
    guard try поля["схема"]!.строка() == "fuma.граф-JSON.1",
      try поля["числа"]!.строка() == "целые64-без-дробей", MemoryLayout<Int>.size == 8
    else { throw ОшибкаИсполнения("граф", "Неизвестная схема или числовой профиль графа") }
    let переменные = try поля["переменные"]!.массив()
    guard переменные.count <= 64 else { throw ОшибкаИсполнения("граф", "Слишком много узлов") }
    var имена: Set<String> = ["вход"]
    for запись in переменные {
      let поля = try запись.объект(["имя", "значение"])
      let имя = try поля["имя"]!.строка()
      try Self.проверитьИмя(имя, среди: имена)
      try Self.проверитьВыражение(поля["значение"]!, имена: имена)
      имена.insert(имя)
    }
    try Self.проверитьВыражение(поля["результат"]!, имена: имена)
  }

  private static func проверитьИмя(_ имя: String, среди имена: Set<String>) throws {
    guard !имя.isEmpty, имя.utf8.count <= 128, !имена.contains(имя),
      имя.unicodeScalars.allSatisfy({ !CharacterSet.controlCharacters.contains($0) })
    else { throw ОшибкаИсполнения("граф", "Повторное, перекрывающее или неверное имя узла") }
  }

  private static func проверитьВыражение(_ узел: УзелОпределения, имена: Set<String>) throws {
    switch узел {
    case .строка, .целое: return
    case .пусто, .логическое:
      throw ОшибкаИсполнения("граф", "Используйте явные null, истина или ложь")
    case .объект(let поля):
      for ключ in поля.keys.sorted() { try проверитьВыражение(поля[ключ]!, имена: имена) }
    case .массив(let части):
      guard let первая = части.first else { throw ОшибкаИсполнения("граф", "Нет операции") }
      let операция = try первая.строка()
      if операция == "переменная" {
        guard части.count == 2 else { throw ОшибкаИсполнения("граф", "Неверная ссылка на узел") }
        let имя = try части[1].строка()
        guard имена.contains(where: { $0.utf8.elementsEqual(имя.utf8) })
        else { throw ОшибкаИсполнения("граф", "Ссылка не ведёт на предшествующий узел") }
        return
      }
      if операция == "отобразить" {
        guard части.count == 4 else { throw ОшибкаИсполнения("граф", "Неверное отображение") }
        try проверитьВыражение(части[1], имена: имена)
        let имя = try части[2].строка()
        try проверитьИмя(имя, среди: имена)
        try проверитьВыражение(части[3], имена: имена.union([имя]))
        return
      }
      let арности: [String: ClosedRange<Int>] = [
        "путь": 2...10, "массив": 0...64, "null": 0...0, "истина": 0...0, "ложь": 0...0,
        "если": 3...3, "равно": 2...2, "не-null": 1...1, "умножить": 2...2,
        "сложить": 2...2, "сумма": 1...1, "длина": 1...1, "в-строку": 1...1,
        "соединить": 1...64, "соединить-массивы": 0...64,
        "потребовать-диапазон": 3...3, "разделить-точно": 2...2,
        "разделить-неотрицательные-вниз": 2...2,
      ]
      guard let арность = арности[операция], арность.contains(части.count - 1) else {
        throw ОшибкаИсполнения("граф", "Неизвестная операция или неверная арность")
      }
      for часть in части.dropFirst() { try проверитьВыражение(часть, имена: имена) }
    }
  }
}

import Foundation

private struct ЗначениеГрафаJSON {
  let узел: УзелОпределения
  let байтов: Int
  let данные: Data
}

extension ГрафJSON {
  func вычислить(_ текст: String, пределБайтов: Int, операция: () throws -> Void) throws -> String {
    // Учитываем разбор конечного входа до создания дерева.
    for _ in текст.utf8 { try операция() }
    var разбор = try РазборОпределения(Data(текст.utf8), входJSON: true)
    let вход = try разбор.разобрать()
    let поля = try узел.объект(["схема", "числа", "переменные", "результат"])

    func ограничить(_ число: Int) throws {
      guard число <= пределБайтов else {
        throw ОшибкаИсполнения("предел-результата", "Промежуточный JSON превышает бюджет")
      }
    }
    func обернуть(_ узел: УзелОпределения) throws -> ЗначениеГрафаJSON {
      var узлов = 0
      func учесть(_ часть: УзелОпределения, глубина: Int) throws {
        guard глубина <= 16, узлов < 8192 else {
          throw ОшибкаИсполнения("предел-структуры", "Промежуточный JSON превышает профиль структуры")
        }
        узлов += 1
        try операция()
        switch часть {
        case .строка(let строка):
          for _ in строка.utf8 { try операция() }
        case .массив(let элементы):
          for элемент in элементы { try учесть(элемент, глубина: глубина + 1) }
        case .объект(let поля):
          for ключ in поля.keys.sorted() {
            for _ in ключ.utf8 { try операция() }
            try учесть(поля[ключ]!, глубина: глубина + 1)
          }
        case .целое, .пусто, .логическое: break
        }
      }
      try учесть(узел, глубина: 0)
      let данные = try каноническиеДанные(узел)
      let размер = данные.count
      try ограничить(размер)
      return ЗначениеГрафаJSON(узел: узел, байтов: размер, данные: данные)
    }
    func точно(_ поля: [String: ЗначениеГрафаJSON], _ ключ: String) throws -> ЗначениеГрафаJSON {
      guard let номер = поля.index(forKey: ключ), поля[номер].key.utf8.elementsEqual(ключ.utf8) else {
        throw ОшибкаИсполнения("граф", "Нет узла с точным именем")
      }
      return поля[номер].value
    }
    func арифметика(_ левое: УзелОпределения, _ правое: УзелОпределения,
                    умножение: Bool) throws -> УзелОпределения {
      for значение in [левое, правое] {
        switch значение {
        case .целое, .пусто: break
        default: throw ОшибкаИсполнения("тип-JSON", "Для арифметики нужны целое или null")
        }
      }
      if левое == .пусто || правое == .пусто { return .пусто }
      let первое = try левое.целое(), второе = try правое.целое()
      let (результат, переполнение) = умножение
        ? первое.multipliedReportingOverflow(by: второе) : первое.addingReportingOverflow(второе)
      guard !переполнение else { throw ОшибкаИсполнения("переполнение-JSON", "Переполнение целого64") }
      return .целое(результат)
    }

    func вычислить(_ выражение: УзелОпределения,
                   среда: [String: ЗначениеГрафаJSON]) throws -> ЗначениеГрафаJSON {
      try операция()
      if case .объект(let записи) = выражение {
        var результат: [String: УзелОпределения] = [:]
        var байтов = 2
        try ограничить(байтов)
        for ключ in записи.keys.sorted() {
          let значение = try вычислить(записи[ключ]!, среда: среда)
          байтов += try каноническиеДанные(УзелОпределения.строка(ключ)).count + 1
            + значение.байтов + (результат.isEmpty ? 0 : 1)
          try ограничить(байтов)
          результат[ключ] = значение.узел
        }
        return try обернуть(.объект(результат))
      }
      guard case .массив(let части) = выражение else { return try обернуть(выражение) }
      let имя = try части[0].строка()
      if имя == "переменная" { return try точно(среда, части[1].строка()) }
      if имя == "если" {
        guard case .логическое(let условие) = try вычислить(части[1], среда: среда).узел else {
          throw ОшибкаИсполнения("тип-JSON", "Условие графа должно быть логическим")
        }
        return try вычислить(части[условие ? 2 : 3], среда: среда)
      }
      if имя == "отобразить" {
        let значения = try вычислить(части[1], среда: среда).узел.массив()
        let локальноеИмя = try части[2].строка()
        var результат: [УзелОпределения] = []
        var байтов = 2
        try ограничить(байтов)
        for значение in значения {
          try операция()
          var локальная = среда
          локальная[локальноеИмя] = try обернуть(значение)
          let часть = try вычислить(части[3], среда: локальная)
          байтов += часть.байтов + (результат.isEmpty ? 0 : 1)
          try ограничить(байтов)
          результат.append(часть.узел)
        }
        return try обернуть(.массив(результат))
      }
      let аргументы = try части.dropFirst().map { try вычислить($0, среда: среда) }
      switch имя {
      case "null": return try обернуть(.пусто)
      case "истина": return try обернуть(.логическое(true))
      case "ложь": return try обернуть(.логическое(false))
      case "массив":
        let размер = 2 + аргументы.reduce(0) { $0 + $1.байтов } + max(0, аргументы.count - 1)
        try ограничить(размер)
        return try обернуть(.массив(аргументы.map(\.узел)))
      case "соединить-массивы":
        var результат: [УзелОпределения] = []
        var размер = 2
        try ограничить(размер)
        for аргумент in аргументы {
          for элемент in try аргумент.узел.массив() {
            try операция()
            let часть = try обернуть(элемент)
            размер += часть.байтов + (результат.isEmpty ? 0 : 1)
            try ограничить(размер)
            результат.append(элемент)
          }
        }
        return try обернуть(.массив(результат))
      case "путь":
        var значение = аргументы[0].узел
        for часть in аргументы.dropFirst() {
          try операция()
          switch значение {
          case .объект(let поля):
            let ключ = try часть.узел.строка()
            guard let номер = поля.index(forKey: ключ), поля[номер].key.utf8.elementsEqual(ключ.utf8) else {
              throw ОшибкаИсполнения("путь-JSON", "Отсутствует обязательное поле JSON")
            }
            значение = поля[номер].value
          case .массив(let элементы):
            let номер = try часть.узел.целое()
            guard элементы.indices.contains(номер) else { throw ОшибкаИсполнения("путь-JSON", "Индекс вне массива") }
            значение = элементы[номер]
          default: throw ОшибкаИсполнения("путь-JSON", "Путь проходит через скаляр")
          }
        }
        return try обернуть(значение)
      case "равно":
        if аргументы[0].байтов == аргументы[1].байтов {
          for _ in 0..<аргументы[0].байтов { try операция() }
        }
        return try обернуть(.логическое(аргументы[0].данные == аргументы[1].данные))
      case "не-null": return try обернуть(.логическое(аргументы[0].узел != .пусто))
      case "умножить", "сложить":
        return try обернуть(арифметика(аргументы[0].узел, аргументы[1].узел, умножение: имя == "умножить"))
      case "потребовать-диапазон":
        let значение = try аргументы[0].узел.целое()
        guard try значение >= аргументы[1].узел.целое(), try значение <= аргументы[2].узел.целое() else {
          throw ОшибкаИсполнения("диапазон-JSON", "Целое вне объявленного диапазона")
        }
        return аргументы[0]
      case "разделить-точно":
        let делитель = try аргументы[1].узел.целое()
        guard делитель != 0 else { throw ОшибкаИсполнения("деление-JSON", "Деление на ноль") }
        if аргументы[0].узел == .пусто { return try обернуть(.пусто) }
        let числитель = try аргументы[0].узел.целое()
        let (частное, переполнение) = числитель.dividedReportingOverflow(by: делитель)
        guard !переполнение, числитель % делитель == 0 else {
          throw ОшибкаИсполнения("деление-JSON", "Переполнение или необходимость явного округления")
        }
        return try обернуть(.целое(частное))
      case "разделить-неотрицательные-вниз":
        let числитель = try аргументы[0].узел.целое()
        let делитель = try аргументы[1].узел.целое()
        guard числитель >= 0, делитель > 0 else {
          throw ОшибкаИсполнения("деление-JSON", "Нужны неотрицательный числитель и положительный делитель")
        }
        return try обернуть(.целое(числитель / делитель))
      case "сумма":
        var сумма = 0
        var неизвестно = false
        for значение in try аргументы[0].узел.массив() {
          try операция()
          if значение == .пусто { неизвестно = true; continue }
          let результат = try арифметика(.целое(сумма), значение, умножение: false)
          сумма = try результат.целое()
        }
        return try обернуть(неизвестно ? .пусто : .целое(сумма))
      case "длина":
        let размер: Int
        switch аргументы[0].узел {
        case .массив(let элементы): размер = элементы.count
        case .объект(let поля): размер = поля.count
        case .строка(let строка): размер = строка.unicodeScalars.count
        default: throw ОшибкаИсполнения("тип-JSON", "Нет длины у скаляра")
        }
        return try обернуть(.целое(размер))
      case "в-строку": return try обернуть(.строка(String(аргументы[0].узел.целое())))
      case "соединить":
        var строка = ""
        var размер = 2
        for аргумент in аргументы {
          let часть = try аргумент.узел.строка()
          размер += аргумент.байтов - 2
          try ограничить(размер)
          строка += часть
        }
        return try обернуть(.строка(строка))
      default: throw ОшибкаИсполнения("граф", "Неизвестный примитив")
      }
    }

    var среда = ["вход": try обернуть(вход)]
    for запись in try поля["переменные"]!.массив() {
      let узел = try запись.объект(["имя", "значение"])
      среда[try узел["имя"]!.строка()] = try вычислить(узел["значение"]!, среда: среда)
    }
    let результат = try вычислить(поля["результат"]!, среда: среда)
    return String(decoding: результат.данные, as: UTF8.self)
  }
}

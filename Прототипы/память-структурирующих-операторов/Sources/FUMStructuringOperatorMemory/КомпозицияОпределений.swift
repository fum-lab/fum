import Foundation

enum ВидЗначенияJSON: String, Sendable {
  case любое = "JSON"
  case целое, строка, объект, массив, логическое
  case пусто = "null"

  func проверить(_ узел: УзелОпределения, код: String) throws {
    let совпало: Bool
    switch (self, узел) {
    case (.любое, _), (.целое, .целое), (.строка, .строка), (.объект, .объект),
      (.массив, .массив), (.логическое, .логическое), (.пусто, .пусто):
      совпало = true
    default: совпало = false
    }
    guard совпало else {
      throw ОшибкаИсполнения(код, "Значение несовместимо с объявленным видом JSON")
    }
  }
}

struct КлючОпределения: Hashable, Sendable {
  let имя: Data
  let версия: Int
  init(_ имя: String, _ версия: Int) {
    self.имя = Data(имя.utf8)
    self.версия = версия
  }
}

struct ЧистоеОпределение: Equatable, Sendable {
  let идентификатор: String
  let версия: Int
  let вход: ВидЗначенияJSON
  let выход: ВидЗначенияJSON
  let граф: ГрафJSON

  var представление: УзелОпределения {
    .объект([
      "идентификатор": .строка(идентификатор), "версия": .целое(версия),
      "вход": .строка(вход.rawValue), "выход": .строка(выход.rawValue), "граф": граф.узел,
    ])
  }

  static func разобрать(_ узел: УзелОпределения) throws -> ЧистоеОпределение {
    let поля = try узел.объект(["идентификатор", "версия", "вход", "выход", "граф"])
    let имя = try поля["идентификатор"]!.строка()
    let версия = try поля["версия"]!.целое()
    guard !имя.isEmpty, имя.utf8.count <= 128, (1...1_000_000).contains(версия),
      имя.unicodeScalars.allSatisfy({ !CharacterSet.controlCharacters.contains($0) }),
      let вход = ВидЗначенияJSON(rawValue: try поля["вход"]!.строка()),
      let выход = ВидЗначенияJSON(rawValue: try поля["выход"]!.строка())
    else {
      throw ОшибкаИсполнения("определение", "Неверная идентичность или вид чистого определения")
    }
    return ЧистоеОпределение(
      идентификатор: имя, версия: версия, вход: вход, выход: выход,
      граф: try ГрафJSON(поля["граф"]!))
  }
}

struct СоставОпределений {
  let определения: [КлючОпределения: ЧистоеОпределение]
  let корень: КлючОпределения

  init(_ оператор: ОпределениеОператора) throws {
    корень = КлючОпределения(оператор.идентификатор, оператор.версия)
    guard оператор.определения.count <= 32 else {
      throw ОшибкаИсполнения("определение", "Слишком много чистых определений")
    }
    var таблица: [КлючОпределения: ЧистоеОпределение] = [:]
    for определение in оператор.определения {
      let ключ = КлючОпределения(определение.идентификатор, определение.версия)
      guard ключ != корень, таблица[ключ] == nil else {
        throw ОшибкаИсполнения(
          "повтор-определения", "Повтор пары определения или коллизия с корнем")
      }
      таблица[ключ] = определение
    }
    определения = таблица
  }

  func найти(_ имя: String, _ версия: Int) throws -> ЧистоеОпределение {
    let ключ = КлючОпределения(имя, версия)
    guard ключ != корень else {
      throw ОшибкаИсполнения("цикл-определений", "Вызов корневого оператора запрещён")
    }
    guard let определение = определения[ключ] else {
      let известен = определения.keys.contains { $0.имя == ключ.имя }
      throw ОшибкаИсполнения(
        известен ? "версия-определения" : "нет-определения",
        "Нет точно закреплённого определения в замыкании")
    }
    return определение
  }

  func проверитьКомпозицию(_ оператор: ОпределениеОператора) throws {
    var активные: Set<КлючОпределения> = []
    var проверенные: Set<КлючОпределения> = []
    func проверить(_ имя: String, _ версия: Int) throws {
      let определение = try найти(имя, версия)
      let ключ = КлючОпределения(имя, версия)
      if проверенные.contains(ключ) { return }
      guard активные.insert(ключ).inserted else {
        throw ОшибкаИсполнения("цикл-определений", "Прямой или косвенный цикл чистых определений")
      }
      for (имя, версия) in определение.граф.вызовы { try проверить(имя, версия) }
      активные.remove(ключ)
      проверенные.insert(ключ)
    }
    // Проверяем и неиспользованные определения, и ленивые ветви до исполнения.
    for определение in оператор.определения {
      try проверить(определение.идентификатор, определение.версия)
    }
    for шаг in оператор.шаги {
      if case .вычислитьJSON(let граф) = шаг.действие {
        for (имя, версия) in граф.вызовы { try проверить(имя, версия) }
      }
    }
  }
}

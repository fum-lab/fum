import Foundation

struct ПолеКонтракта: Equatable, Sendable {
  let имя: String
  let ключ: String
  let тип: String
  let обязательно: Bool
  let допускаетNull: Bool
  let варианты: [String]
}

struct МодельКонтракта: Equatable, Sendable {
  let имя: String
  let идентификатор: String
  let поля: [ПолеКонтракта]
}

// Конечное структурное значение создаётся только закрытым разбором и проверкой.
public struct СтруктурныйКонтракт: Equatable, Sendable {
  let узел: УзелОпределения
  let данные: Data
  let модели: [МодельКонтракта]
  let вход: String
  let выход: String
  let стоимость: Int

  init(_ данные: Data) throws {
    var разбор = try РазборОпределения(данные)
    let узел = try разбор.разобрать()
    let поля = try узел.объект([
      "схема", "идентификатор", "версия", "происхождение", "модели", "вход", "выход",
      "переменные", "результат", "числа",
    ])
    guard try поля["схема"]!.строка() == "fum.структурный-контракт.1",
      try поля["версия"]!.целое() == 1,
      !(try поля["идентификатор"]!.строка()).isEmpty,
      !(try поля["происхождение"]!.строка()).isEmpty
    else { throw ОшибкаИсполнения("контракт", "Неизвестная версия или отсутствие происхождения") }
    guard try поля["числа"]!.строка() == "целые64-без-дробей" else {
      throw ОшибкаИсполнения("контракт", "Нужен явный поддержанный числовой профиль")
    }
    let модели = try поля["модели"]!.массив().map { узел in
      let модель = try узел.объект(["имя", "идентификатор", "поля"])
      let имя = try модель["имя"]!.строка()
      try Self.проверитьИмя(имя)
      try Self.проверитьОбъявление(имя)
      let поля = try модель["поля"]!.массив().map { узел in
        let поле = try узел.объект(["имя", "ключ", "тип", "присутствие", "null", "варианты"])
        let имя = try поле["имя"]!.строка()
        let ключ = try поле["ключ"]!.строка()
        try Self.проверитьИмя(имя)
        try Self.проверитьОбъявление(имя)
        guard !ключ.isEmpty, ключ.utf8.count <= 128,
          !ключ.unicodeScalars.contains(where: CharacterSet.controlCharacters.contains)
        else { throw ОшибкаИсполнения("контракт", "Недопустимый ключ модели") }
        let присутствие = try поле["присутствие"]!.строка()
        let null = try поле["null"]!.строка()
        guard ["обязательно", "необязательно"].contains(присутствие), ["да", "нет"].contains(null)
        else { throw ОшибкаИсполнения("контракт", "Присутствие и null задаются отдельно") }
        let варианты = try поле["варианты"]!.массив().map { try $0.строка() }
        guard Set(варианты).count == варианты.count, варианты.count <= 32 else {
          throw ОшибкаИсполнения("контракт", "Неоднозначные варианты значения")
        }
        return ПолеКонтракта(имя: имя, ключ: ключ, тип: try поле["тип"]!.строка(),
          обязательно: присутствие == "обязательно", допускаетNull: null == "да", варианты: варианты)
      }
      guard (1...64).contains(поля.count), Set(поля.map(\.имя)).count == поля.count,
        Set(поля.map(\.ключ)).count == поля.count else {
        throw ОшибкаИсполнения("контракт", "Повтор имени, ключа или неверное число полей")
      }
      return МодельКонтракта(имя: имя, идентификатор: try модель["идентификатор"]!.строка(), поля: поля)
    }
    let имена = Set(модели.map(\.имя))
    guard (1...32).contains(модели.count), имена.count == модели.count,
      Set(модели.map(\.идентификатор)).count == модели.count,
      модели.allSatisfy({ !$0.идентификатор.isEmpty }) else {
      throw ОшибкаИсполнения("контракт", "Неоднозначные модели или идентификаторы")
    }
    for модель in модели {
      for поле in модель.поля {
        _ = try Self.тип(поле.тип, язык: "Swift", модели: имена)
        guard поле.варианты.isEmpty || поле.тип == "строка" else {
          throw ОшибкаИсполнения("контракт", "Строковые варианты требуют строковый тип")
        }
      }
    }
    var завершены: Set<String> = []
    func проверитьСвязи(_ имя: String, путь: Set<String>) throws {
      if завершены.contains(имя) { return }
      guard !путь.contains(имя) else { throw ОшибкаИсполнения("контракт", "Рекурсивная модель не поддержана") }
      let модель = модели.first { $0.имя == имя }!
      for поле in модель.поля {
        let части = поле.тип.components(separatedBy: CharacterSet(charactersIn: "<>"))
        for ссылка in части where имена.contains(ссылка) {
          try проверитьСвязи(ссылка, путь: путь.union([имя]))
        }
      }
      завершены.insert(имя)
    }
    for имя in имена.sorted() { try проверитьСвязи(имя, путь: []) }
    let вход = try поля["вход"]!.строка(), выход = try поля["выход"]!.строка()
    guard имена.contains(вход), имена.contains(выход) else {
      throw ОшибкаИсполнения("контракт", "Нет входной или выходной модели")
    }
    var переменные: Set<String> = ["вход", "артефакт", "ожидаемаяЗадача"]
    var стоимость = модели.reduce(1) { $0 + $1.поля.count }
    for запись in try поля["переменные"]!.массив() {
      let запись = try запись.объект(["имя", "значение"])
      let имя = try запись["имя"]!.строка()
      try Self.проверитьИмя(имя)
      guard !переменные.contains(имя) else { throw ОшибкаИсполнения("контракт", "Повтор переменной") }
      стоимость += try Self.проверитьВыражение(запись["значение"]!, переменные: переменные)
      переменные.insert(имя)
    }
    стоимость += try Self.проверитьВыражение(поля["результат"]!, переменные: переменные)
    guard case .объект(let результат) = поля["результат"]! else {
      throw ОшибкаИсполнения("контракт", "Результат должен явно собирать выходную модель")
    }
    let выходныеПоля = модели.first { $0.имя == выход }!.поля
    let ключи = Set(результат.keys.map { Data($0.utf8) })
    guard ключи.isSubset(of: Set(выходныеПоля.map { Data($0.ключ.utf8) })),
      Set(выходныеПоля.filter(\.обязательно).map { Data($0.ключ.utf8) }).isSubset(of: ключи) else {
      throw ОшибкаИсполнения("контракт", "Ключи результата не соответствуют выходной модели")
    }
    self.узел = узел
    self.данные = try каноническиеДанные(узел)
    self.модели = модели
    self.вход = вход
    self.выход = выход
    self.стоимость = стоимость
  }

  private static func проверитьИмя(_ имя: String) throws {
    guard имя.utf8.count <= 128,
      имя.range(of: "^[А-Яа-яЁё][А-Яа-яЁё0-9_]*$", options: .regularExpression) != nil else {
      throw ОшибкаИсполнения("контракт", "Нужно однозначное кириллическое имя объявления")
    }
  }

  private static func проверитьОбъявление(_ имя: String) throws {
    let служебные: Set<String> = ["КонтрактМоделей", "Поле", "ПолеJSON", "ЗначениеJSON", "Ключи",
      "описание_моделей", "описаниеМоделей", "модели", "спроецировать", "представить_снимок",
      "представитьСнимок", "подготовить_снимок", "ограничить_выход", "прочитатьПоле", "записатьПоле",
      "подготовитьСнимок", "ограничитьВыход", "строка", "целое", "логическое", "массив", "словарь"]
    guard !служебные.contains(имя) else { throw ОшибкаИсполнения("контракт", "Имя перекрывает служебное объявление") }
  }

  // Известный вид константы проверяется до генерации; динамические пути проверяет runtime.
  private static func вид(_ узел: УзелОпределения) -> String? {
    switch узел {
    case .строка: return "строка"
    case .целое: return "целое"
    case .объект: return "объект"
    case .массив(let части):
      guard case .строка(let операция) = части.first else { return nil }
      switch операция {
      case "массив", "собрать-вложенные": return "массив"
      case "группировать", "убрать-выбранный", "разобрать-JSON": return "объект"
      case "истина", "ложь", "равно", "не-null", "потребовать-равно", "проверить-варианты",
        "потребовать-ложь-или-отсутствие", "потребовать-положительное": return "логическое"
      case "вычесть", "длина", "считать-не-null": return "целое"
      case "указатель": return "строка"
      case "null": return "null"
      default: return nil
      }
    }
  }

  private static func проверитьАргументы(_ операция: String, _ аргументы: [УзелОпределения]) throws {
    var требования: [Int: Set<String>] = [:]
    switch операция {
    case "если": требования = [0: ["логическое"]]
    case "первый", "указатель": требования = [0: ["массив"]]
    case "вычесть": требования = [0: ["целое"], 1: ["целое"]]
    case "потребовать-положительное": требования = [0: ["целое"]]
    case "длина": требования = [0: ["массив", "объект", "строка"]]
    case "без-полей": требования = [0: ["объект", "null"], 1: ["массив"]]
    case "путь": требования = [0: ["объект", "массив", "null"]]
    case "собрать-вложенные", "группировать", "считать-не-null": требования = [0: ["массив"], 1: ["строка"]]
    case "проверить-варианты": требования = [0: ["массив"], 1: ["строка"], 2: ["объект"]]
    case "выбрать-вложенный": требования = [0: ["массив"], 1: ["строка"], 2: ["строка"], 4: ["строка"], 5: ["массив"]]
    case "убрать-выбранный": требования = [0: ["объект"], 1: ["строка", "null"]]
    case "разобрать-JSON": требования = [0: ["строка"], 1: ["строка"]]
    default: break
    }
    for (номер, допустимые) in требования {
      if let вид = вид(аргументы[номер]), !допустимые.contains(вид) {
        throw ОшибкаИсполнения("контракт", "Известный тип аргумента не соответствует операции")
      }
    }
  }

  static func тип(_ имя: String, язык: String, модели: Set<String>, глубина: Int = 0) throws -> String {
    guard глубина <= 2 else { throw ОшибкаИсполнения("контракт", "Слишком вложенный тип") }
    let простые = язык == "Swift"
      ? ["строка": "String", "целое": "Int64", "логическое": "Bool", "JSON": "ЗначениеJSON"]
      : ["строка": "str", "целое": "int", "логическое": "bool", "JSON": "object"]
    if let тип = простые[имя] { return тип }
    if модели.contains(имя) { return имя }
    for род in ["массив", "словарь"] where имя.hasPrefix(род + "<") && имя.hasSuffix(">") {
      let вложенный = String(имя.dropFirst(род.count + 1).dropLast())
      let тип = try тип(вложенный, язык: язык, модели: модели, глубина: глубина + 1)
      return язык == "Swift" ? (род == "массив" ? "[\(тип)]" : "[String: \(тип)]")
        : (род == "массив" ? "list[\(тип)]" : "dict[str, \(тип)]")
    }
    throw ОшибкаИсполнения("контракт", "Неподдержанный тип поля")
  }

  private static func проверитьВыражение(_ узел: УзелОпределения, переменные: Set<String>) throws -> Int {
    switch узел {
    case .целое, .строка: return 1
    case .объект(let поля):
      return try поля.values.reduce(1) { try $0 + проверитьВыражение($1, переменные: переменные) }
    case .массив(let части):
      guard let первая = части.first else { throw ОшибкаИсполнения("контракт", "Нет операции выражения") }
      let операция = try первая.строка()
      if операция == "переменная" {
        guard части.count == 2, переменные.contains(try части[1].строка()) else {
          throw ОшибкаИсполнения("контракт", "Неизвестная переменная")
        }
        return 1
      }
      let арности: [String: ClosedRange<Int>] = [
        "путь": 2...10, "массив": 0...64, "null": 0...0, "истина": 0...0, "ложь": 0...0,
        "первый": 1...1, "без-полей": 2...2, "равно": 2...2, "не-null": 1...1,
        "если": 3...3, "длина": 1...1, "вычесть": 2...2,
        "выбрать-вложенный": 6...6, "собрать-вложенные": 2...2,
        "группировать": 2...2, "убрать-выбранный": 2...2, "считать-не-null": 2...2,
        "указатель": 1...1, "потребовать-равно": 2...2, "проверить-варианты": 3...3,
        "разобрать-JSON": 2...2, "потребовать-ложь-или-отсутствие": 1...1,
        "потребовать-положительное": 1...1,
      ]
      guard let арность = арности[операция], арность.contains(части.count - 1) else {
        throw ОшибкаИсполнения("контракт", "Неизвестная операция или арность проекции")
      }
      let стоимость = try части.dropFirst().reduce(1) { try $0 + проверитьВыражение($1, переменные: переменные) }
      try проверитьАргументы(операция, Array(части.dropFirst()))
      return стоимость
    }
  }

  func породить(язык: String, профиль: String) throws -> String {
    guard ["Swift", "Python"].contains(язык), профиль == "fum.модели-и-проекция.1" else {
      throw ОшибкаИсполнения("контракт", "Неизвестный профиль генератора")
    }
    return try ПорождениеМоделей.породить(self, язык: язык, профиль: профиль)
  }
}

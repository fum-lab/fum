import Foundation

// Языковой вывод принимает проверенное общее представление, а не готовые предметные шаблоны.
enum ПорождениеМоделей {
  static func породить(_ контракт: СтруктурныйКонтракт, язык: String, профиль: String) throws
    -> String
  {
    func литерал(_ текст: String) -> String {
      if язык == "Swift" { return String(reflecting: текст) }
      let кодировщик = JSONEncoder()
      кодировщик.outputFormatting = [.withoutEscapingSlashes]
      return String(decoding: try! кодировщик.encode(текст), as: UTF8.self)
    }
    let имена = Set(контракт.модели.map(\.имя))
    let данные = контракт.данные.base64EncodedString()
    let символы = Array(данные)
    let фрагменты = stride(from: 0, to: символы.count, by: 120).map {
      литерал(String(символы[$0..<min($0 + 120, символы.count)]))
    }
    if язык == "Python" {
      var строки =
        [
          "# Порождён структурирующими операторами; профиль \(профиль). Ручные правки запрещены.",
          "from __future__ import annotations", "from dataclasses import dataclass",
          "from поддержка_моделей import Поле, КонтрактМоделей, подготовить_снимок, ограничить_выход",
          "",
          "# Каноническое описание: \(sha256Digest(контракт.данные))",
          "описание_моделей = КонтрактМоделей(",
        ] + фрагменты.map { "    " + $0 } + [")", ""]
      for модель in контракт.модели {
        строки += ["@dataclass(frozen=True)", "class \(модель.имя):"]
        for поле in модель.поля {
          var тип = try СтруктурныйКонтракт.тип(поле.тип, язык: язык, модели: имена)
          if !поле.обязательно || поле.допускаетПустойМаркер { тип = "Поле[\(тип)]" }
          строки.append("    \(поле.имя): \(тип)")
        }
        строки += [
          "", "    @classmethod", "    def из_JSON(класс, значение):",
          "        return описание_моделей.прочитать_модель(класс, значение, модели)", "",
          "    def в_JSON(значение):", "        return описание_моделей.записать_модель(значение)",
          "",
        ]
      }
      строки += [
        "модели = {"
          + контракт.модели.map { "\(литерал($0.имя)): \($0.имя)" }.joined(separator: ", ") + "}",
        "",
        "def спроецировать(вход: \(контракт.вход), артефакт, ожидаемая_задача) -> \(контракт.выход):",
        "    результат = описание_моделей.спроецировать(вход.в_JSON(), артефакт, ожидаемая_задача)",
        "    return \(контракт.выход).из_JSON(результат)", "",
        "def представить_снимок(данные, ожидаемый_хэш, задача, максимум_байтов=16000):",
        "    значение, артефакт = подготовить_снимок(данные, ожидаемый_хэш, задача)",
        "    вход = \(контракт.вход).из_JSON(значение)",
        "    return ограничить_выход(спроецировать(вход, артефакт, задача).в_JSON(), максимум_байтов)",
        "",
      ]
      return строки.joined(separator: "\n")
    }
    var строки =
      [
        "// Порождён структурирующими операторами; профиль \(профиль). Ручные правки запрещены.",
        "import Foundation", "import ПоддержкаОтвета", "",
        "// Каноническое описание: \(sha256Digest(контракт.данные))",
        "private let описаниеМоделей = try! КонтрактМоделей(кодированноеОписание: [",
      ] + фрагменты.map { "  " + $0 + "," } + ["].joined())", ""]
    for модель in контракт.модели {
      строки.append("public struct \(модель.имя): Codable, Sendable {")
      for поле in модель.поля {
        var тип = try СтруктурныйКонтракт.тип(поле.тип, язык: язык, модели: имена)
        if !поле.обязательно || поле.допускаетПустойМаркер { тип = "ПолеJSON<\(тип)>" }
        строки.append("  public let \(поле.имя): \(тип)")
      }
      строки += ["", "  private enum Ключи: String, CodingKey {"]
      строки += модель.поля.map { "    case \($0.имя) = \(литерал($0.ключ))" }
      строки += [
        "  }", "", "  public init(from декодер: any Decoder) throws {",
        "    try описаниеМоделей.проверить(ЗначениеJSON(from: декодер), модель: \(литерал(модель.имя)))",
        "    let контейнер = try декодер.container(keyedBy: Ключи.self)",
      ]
      for поле in модель.поля {
        let тип = try СтруктурныйКонтракт.тип(поле.тип, язык: язык, модели: имена)
        if поле.обязательно && !поле.допускаетПустойМаркер {
          строки.append(
            "    self.\(поле.имя) = try контейнер.decode(\(тип).self, forKey: .\(поле.имя))")
        } else {
          строки.append(
            "    self.\(поле.имя) = try прочитатьПоле(\(тип).self, из: контейнер, ключ: .\(поле.имя))"
          )
        }
      }
      строки += [
        "  }", "", "  public func encode(to кодировщик: any Encoder) throws {",
        "    var контейнер = кодировщик.container(keyedBy: Ключи.self)",
      ]
      for поле in модель.поля {
        if поле.обязательно && !поле.допускаетПустойМаркер {
          строки.append("    try контейнер.encode(self.\(поле.имя), forKey: .\(поле.имя))")
        } else {
          строки.append(
            "    try записатьПоле(self.\(поле.имя), в: &контейнер, ключ: .\(поле.имя), обязательно: \(поле.обязательно))"
          )
        }
      }
      строки += ["  }", "}", ""]
    }
    строки += [
      "public func спроецировать(_ вход: \(контракт.вход), артефакт: ЗначениеJSON, ожидаемаяЗадача: String) throws -> \(контракт.выход) {",
      "  let данные = try JSONEncoder().encode(вход)",
      "  let значение = try JSONDecoder().decode(ЗначениеJSON.self, from: данные)",
      "  let результат = try описаниеМоделей.спроецировать(значение, артефакт: артефакт, ожидаемаяЗадача: ожидаемаяЗадача)",
      "  return try JSONDecoder().decode(\(контракт.выход).self, from: JSONEncoder().encode(результат))",
      "}", "",
      "public func представитьСнимок(_ данные: Data, ожидаемыйХэш: String, задача: String, максимумБайтов: Int = 16000) throws -> Data {",
      "  let артефакт = try подготовитьСнимок(данные, ожидаемыйХэш: ожидаемыйХэш, задача: задача)",
      "  let вход = try JSONDecoder().decode(\(контракт.вход).self, from: данные)",
      "  let результат = try спроецировать(вход, артефакт: артефакт, ожидаемаяЗадача: задача)",
      "  return try ограничитьВыход(JSONEncoder().encode(результат), максимумБайтов: максимумБайтов)",
      "}", "",
    ]
    return строки.joined(separator: "\n")
  }

}

import Foundation

public struct ПолеSFNT: Equatable, Sendable {
  public let значение: UInt64
  public let диапазонИсходныхБайтов: Range<Int>
}

public struct ТаблицаSFNT: Equatable, Sendable {
  public let тег: String
  public let контрольнаяСумма: ПолеSFNT
  public let смещение: ПолеSFNT
  public let длина: ПолеSFNT
}

public struct ЗаголовокSFNT: Equatable, Sendable {
  public let версия: ПолеSFNT
  public let числоТаблиц: ПолеSFNT
  public let таблицы: [ТаблицаSFNT]
}

public enum ОшибкаSFNT: Error, Equatable, Sendable {
  case невернаяПодпись
  case невернаяВерсия(значение: UInt64)
  case недопустимоеЧислоТаблиц(значение: UInt64)
  case переполнениеТаблицы(тег: String, смещение: UInt64, длина: UInt64)
  case таблицаВЗаголовке(тег: String)
  case повторТега(String)
}

/// Разбирает только заголовок и directory sfnt TrueType; контуры и cmap сюда не входят.
public enum ОператорРазбораSFNT {
  public static func выполнить(_ байты: [UInt8]) throws -> ЗаголовокSFNT {
    let читатель = ЧитательБайтов(байты)
    guard try читатель.прочитатьБеззнаковое(соСмещения: 0, длиной: 4, порядок: .старшийПервым).значение == 0x00010000
    else { throw ОшибкаSFNT.невернаяПодпись }

    let версия = try поле(читатель, 0, 4)
    let число = try поле(читатель, 4, 2)
    guard (1...4096).contains(Int(число.значение)) else {
      throw ОшибкаSFNT.недопустимоеЧислоТаблиц(значение: число.значение)
    }
    _ = try читатель.прочитатьБеззнаковое(
      соСмещения: 6, длиной: 6, порядок: .старшийПервым)

    var таблицы: [ТаблицаSFNT] = []
    var теги: Set<String> = []
    for номер in 0..<Int(число.значение) {
      let начало = 12 + номер * 16
      let тэгБайты = try (0..<4).map {
        UInt8(try читатель.прочитатьБеззнаковое(
          соСмещения: начало + $0, длиной: 1, порядок: .старшийПервым).значение)
      }
      guard тэгБайты.allSatisfy({ (0x20...0x7e).contains($0) }),
        let тэг = String(bytes: тэгБайты, encoding: .ascii)
      else { throw ОшибкаSFNT.невернаяПодпись }
      guard теги.insert(тэг).inserted else { throw ОшибкаSFNT.повторТега(тэг) }
      let контрольнаяСумма = try поле(читатель, начало + 4, 4)
      let смещение = try поле(читатель, начало + 8, 4)
      let длина = try поле(читатель, начало + 12, 4)
      let (конец, переполнено) = смещение.значение.addingReportingOverflow(длина.значение)
      guard !переполнено, конец <= UInt64(байты.count) else {
        throw ОшибкаSFNT.переполнениеТаблицы(тег: тэг, смещение: смещение.значение, длина: длина.значение)
      }
      guard смещение.значение >= 12 + число.значение * 16 else {
        throw ОшибкаSFNT.таблицаВЗаголовке(тег: тэг)
      }
      таблицы.append(.init(тег: тэг, контрольнаяСумма: контрольнаяСумма, смещение: смещение, длина: длина))
    }
    return .init(версия: версия, числоТаблиц: число, таблицы: таблицы)
  }

  private static func поле(_ читатель: ЧитательБайтов, _ смещение: Int, _ длина: Int) throws -> ПолеSFNT {
    let результат = try читатель.прочитатьБеззнаковое(
      соСмещения: смещение, длиной: длина, порядок: .старшийПервым)
    return ПолеSFNT(значение: результат.значение, диапазонИсходныхБайтов: результат.диапазонИсходныхБайтов)
  }
}

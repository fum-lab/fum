public struct ПрочитанноеБеззнаковоеЧисло: Equatable, Sendable {
  public let значение: UInt64
  public let диапазонИсходныхБайтов: Range<Int>

  public init(значение: UInt64, диапазонИсходныхБайтов: Range<Int>) {
    self.значение = значение
    self.диапазонИсходныхБайтов = диапазонИсходныхБайтов
  }
}

public enum ОшибкаЧтенияБайтов: Error, Equatable, Sendable {
  case недопустимаяДлина(числоБайтов: Int)
  case отрицательноеСмещение(смещение: Int)
  case переполнениеКонечногоСмещения(смещение: Int, числоБайтов: Int)
  case внеВхода(смещение: Int, числоБайтов: Int, размерВхода: Int)
}

public struct ЧитательБайтов: Sendable {
  private let байты: [UInt8]

  public init(_ байты: [UInt8]) {
    self.байты = байты
  }

  public func прочитатьБеззнаковое(
    соСмещения смещение: Int,
    длиной числоБайтов: Int,
    порядок: ПорядокБайтов
  ) throws -> ПрочитанноеБеззнаковоеЧисло {
    guard (1...8).contains(числоБайтов) else {
      throw ОшибкаЧтенияБайтов.недопустимаяДлина(числоБайтов: числоБайтов)
    }
    guard смещение >= 0 else {
      throw ОшибкаЧтенияБайтов.отрицательноеСмещение(смещение: смещение)
    }

    let (конец, переполнено) = смещение.addingReportingOverflow(числоБайтов)
    guard !переполнено else {
      throw ОшибкаЧтенияБайтов.переполнениеКонечногоСмещения(
        смещение: смещение,
        числоБайтов: числоБайтов
      )
    }
    guard конец <= байты.count else {
      throw ОшибкаЧтенияБайтов.внеВхода(
        смещение: смещение,
        числоБайтов: числоБайтов,
        размерВхода: байты.count
      )
    }

    var значение: UInt64 = 0
    switch порядок {
    case .старшийПервым:
      for индекс in смещение..<конец {
        значение = (значение << 8) | UInt64(байты[индекс])
      }
    case .младшийПервым:
      for индекс in 0..<числоБайтов {
        значение |= UInt64(байты[смещение + индекс]) << (индекс * 8)
      }
    }

    return ПрочитанноеБеззнаковоеЧисло(
      значение: значение,
      диапазонИсходныхБайтов: смещение..<конец
    )
  }
}

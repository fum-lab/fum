import Foundation

public struct ОшибкаИсполнения: Error, Equatable, Encodable, Sendable {
  public let код: String
  public let пояснение: String
  public let позицияБайта: Int?
  public let началоПоследовательности: Int?

  init(
    _ код: String, _ пояснение: String, позицияБайта: Int? = nil,
    началоПоследовательности: Int? = nil
  ) {
    self.код = код
    self.пояснение = пояснение
    self.позицияБайта = позицияБайта
    self.началоПоследовательности = началоПоследовательности
  }
}

public enum ЗначениеОператора: Equatable, Encodable, Sendable {
  case текст(String)
  case байты([UInt8])
  case скаляры([UInt32])

  var вид: String {
    switch self {
    case .текст: return "текст"
    case .байты: return "байты"
    case .скаляры: return "скаляры"
    }
  }

  var размер: Int {
    switch self {
    case .текст(let текст): return текст.utf8.count
    case .байты(let байты): return байты.count
    case .скаляры(let скаляры): return скаляры.count * 4
    }
  }

  var исходныеБайты: Data {
    switch self {
    case .текст(let текст): return Data(текст.utf8)
    case .байты(let байты): return Data(байты)
    case .скаляры(let скаляры):
      var данные = Data(count: скаляры.count * 4)
      данные.withUnsafeMutableBytes { (буфер: UnsafeMutableRawBufferPointer) in
        for (номер, скаляр) in скаляры.enumerated() {
          for байт in 0..<4 {
            буфер[номер * 4 + байт] = UInt8(truncatingIfNeeded: скаляр >> ((3 - байт) * 8))
          }
        }
      }
      return данные
    }
  }

  private enum Ключи: String, CodingKey { case тип, значение }

  public func encode(to кодировщик: any Encoder) throws {
    var контейнер = кодировщик.container(keyedBy: Ключи.self)
    try контейнер.encode(вид, forKey: .тип)
    switch self {
    case .текст(let текст): try контейнер.encode(текст, forKey: .значение)
    case .байты(let байты): try контейнер.encode(байты, forKey: .значение)
    case .скаляры(let скаляры): try контейнер.encode(скаляры, forKey: .значение)
    }
  }
}

public struct ПределыИсполнения: Equatable, Sendable {
  public let байтовВхода: Int
  public let байтовРезультата: Int
  public let операций: Int
  public let записейТрассы: Int

  public init(
    байтовВхода: Int = 262_144, байтовРезультата: Int = 1_048_576,
    операций: Int = 16_777_216, записейТрассы: Int = 256
  ) {
    self.байтовВхода = байтовВхода
    self.байтовРезультата = байтовРезультата
    self.операций = операций
    self.записейТрассы = записейТрассы
  }

  func проверить() throws {
    guard (0...262_144).contains(байтовВхода), (0...1_048_576).contains(байтовРезультата),
      (1...16_777_216).contains(операций), (0...256).contains(записейТрассы)
    else { throw ОшибкаИсполнения("пределы", "Пределы можно только уменьшать") }
  }
}

public struct СледШагаОператора: Equatable, Encodable, Sendable {
  public let идентификатор: String
  public let хэшВхода: String
  public let хэшВыхода: String
}

public struct СледПравилаОператора: Equatable, Encodable, Sendable {
  public let шаг: String
  public let правило: String
  public let позицияБайта: Int
  public let длина: Int
  public let скаляр: UInt32
}

public struct НаблюдениеОператора: Equatable, Encodable, Sendable {
  public let схема = "fum.наблюдение-оператора.1"
  public let версияОпределения: Int
  public let хэшОпределения: String
  public let хэшИсходныхБайтов: String
  public let типВхода: String
  public let результат: ЗначениеОператора
  public let скаляры: [UInt32]?
  public let шаги: [СледШагаОператора]
  public let трасса: [СледПравилаОператора]
  public let пропущеноЗаписей: Int
  public let выполненоОпераций: Int
  public let хэшНаблюдения: String
}

public struct ЗамерИсполнения: Encodable, Sendable {
  public let стадия: String
  public let наносекунды: UInt64
  public let исход: String

  public init(стадия: String, наносекунды: UInt64, исход: String) {
    self.стадия = стадия
    self.наносекунды = наносекунды
    self.исход = исход
  }
}

private struct СчётчикИсполнения {
  let пределы: ПределыИсполнения
  var выполнено = 0
  var трасса: [СледПравилаОператора] = []
  var пропущено = 0
  var времяТрассы: UInt64 = 0

  mutating func операция() throws {
    guard выполнено < пределы.операций else {
      throw ОшибкаИсполнения("предел-операций", "Исчерпан бюджет общих операций")
    }
    выполнено += 1
  }

  mutating func записать(_ запись: СледПравилаОператора) {
    let начало = DispatchTime.now().uptimeNanoseconds
    if трасса.count < пределы.записейТрассы { трасса.append(запись) } else { пропущено += 1 }
    времяТрассы += DispatchTime.now().uptimeNanoseconds - начало
  }
}

extension AutomationExecutor {
  public static func выполнить(
    _ определение: ОпределениеОператора, вход: ЗначениеОператора,
    пределы: ПределыИсполнения = ПределыИсполнения(),
    профиль: ((ЗамерИсполнения) -> Void)? = nil
  ) throws -> НаблюдениеОператора {
    let началоПроверки = DispatchTime.now().uptimeNanoseconds
    do {
      try пределы.проверить()
      try определение.проверить()
      guard вход.размер <= пределы.байтовВхода else {
        throw ОшибкаИсполнения("предел-входа", "Превышен размер отдельного входа")
      }
      if case .скаляры(let скаляры) = вход, !скаляры.allSatisfy(допустимыйСкаляр) {
        throw ОшибкаИсполнения("скаляр", "Вход содержит значение вне множества Unicode-скаляров")
      }
      профиль?(
        ЗамерИсполнения(
          стадия: "проверка",
          наносекунды:
            DispatchTime.now().uptimeNanoseconds - началоПроверки, исход: "успешно"))
    } catch {
      профиль?(
        ЗамерИсполнения(
          стадия: "проверка",
          наносекунды:
            DispatchTime.now().uptimeNanoseconds - началоПроверки, исход: "отказ"))
      throw error
    }
    var счётчик = СчётчикИсполнения(пределы: пределы)
    let началоИсполнения = DispatchTime.now().uptimeNanoseconds
    var текущий = вход
    var скаляры: [UInt32]?
    var шаги: [СледШагаОператора] = []
    do {
      for шаг in определение.шаги {
        try счётчик.операция()
        let началоХэша = DispatchTime.now().uptimeNanoseconds
        let хэшВхода = sha256Digest(текущий.исходныеБайты)
        счётчик.времяТрассы += DispatchTime.now().uptimeNanoseconds - началоХэша
        switch шаг.действие {
        case .повторитьПравила(let имена):
          guard case .байты(let байты) = текущий else {
            throw ОшибкаИсполнения("тип-входа", "Повтор правил принимает исходные байты")
          }
          let правила = имена.map { имя in определение.правила.first { $0.идентификатор == имя }! }
          let значения = try повторить(
            правила, байты: байты, шаг: шаг.идентификатор,
            счётчик: &счётчик)
          скаляры = значения
          текущий = .скаляры(значения)
        case .упаковатьСлова(let ширина, let порядок):
          guard case .скаляры(let значения) = текущий else {
            throw ОшибкаИсполнения("тип-входа", "Упаковка слов принимает скаляры")
          }
          guard значения.count <= пределы.байтовРезультата / ширина else {
            throw ОшибкаИсполнения("предел-результата", "Упакованные слова превышают бюджет")
          }
          скаляры = значения
          var байты: [UInt8] = []
          байты.reserveCapacity(значения.count * ширина)
          for значение in значения {
            try счётчик.операция()
            guard ширина == 4 || UInt64(значение) < (UInt64(1) << (ширина * 8)) else {
              throw ОшибкаИсполнения("ширина-слова", "Скаляр не помещается в выбранное слово")
            }
            for номер in 0..<ширина {
              let сдвиг = (порядок == .младшийПервым ? номер : ширина - номер - 1) * 8
              байты.append(UInt8(truncatingIfNeeded: значение >> сдвиг))
            }
          }
          текущий = .байты(байты)
        default:
          guard case .текст(let текст) = текущий else {
            throw ОшибкаИсполнения("тип-входа", "Текстовый оператор принимает текст")
          }
          текущий = .текст(try изменитьТекст(текст, действие: шаг.действие, счётчик: &счётчик))
        }
        guard текущий.размер <= пределы.байтовРезультата else {
          throw ОшибкаИсполнения("предел-результата", "Превышен бюджет результата")
        }
        let началоСледа = DispatchTime.now().uptimeNanoseconds
        шаги.append(
          СледШагаОператора(
            идентификатор: шаг.идентификатор,
            хэшВхода: хэшВхода, хэшВыхода: sha256Digest(текущий.исходныеБайты)))
        счётчик.времяТрассы += DispatchTime.now().uptimeNanoseconds - началоСледа
      }
      guard текущий.размер <= пределы.байтовРезультата else {
        throw ОшибкаИсполнения("предел-результата", "Превышен бюджет результата")
      }
    } catch {
      профиль?(
        ЗамерИсполнения(
          стадия: "исполнение",
          наносекунды:
            DispatchTime.now().uptimeNanoseconds - началоИсполнения - счётчик.времяТрассы,
          исход: "отказ"))
      профиль?(ЗамерИсполнения(стадия: "трасса", наносекунды: счётчик.времяТрассы, исход: "отказ"))
      throw error
    }
    профиль?(
      ЗамерИсполнения(
        стадия: "исполнение",
        наносекунды:
          DispatchTime.now().uptimeNanoseconds - началоИсполнения - счётчик.времяТрассы,
        исход: "успешно"))
    let началоТрассы = DispatchTime.now().uptimeNanoseconds
    let хэшОпределения = sha256Digest(try каноническиеДанные(определение.представление))
    let хэшВхода = sha256Digest(вход.исходныеБайты)
    // Хэш содержит тип входа, определение, результат и точную ограниченную трассу.
    let безХэша = НаблюдениеОператора(
      версияОпределения: определение.версия,
      хэшОпределения: хэшОпределения, хэшИсходныхБайтов: хэшВхода, типВхода: вход.вид,
      результат: текущий, скаляры: скаляры, шаги: шаги, трасса: счётчик.трасса,
      пропущеноЗаписей: счётчик.пропущено, выполненоОпераций: счётчик.выполнено,
      хэшНаблюдения: "")
    let результат = НаблюдениеОператора(
      версияОпределения: определение.версия,
      хэшОпределения: хэшОпределения, хэшИсходныхБайтов: хэшВхода, типВхода: вход.вид,
      результат: текущий, скаляры: скаляры, шаги: шаги, трасса: счётчик.трасса,
      пропущеноЗаписей: счётчик.пропущено, выполненоОпераций: счётчик.выполнено,
      хэшНаблюдения: sha256Digest(try каноническиеДанные(безХэша)))
    профиль?(
      ЗамерИсполнения(
        стадия: "трасса",
        наносекунды:
          счётчик.времяТрассы + DispatchTime.now().uptimeNanoseconds - началоТрассы,
        исход: "успешно"))
    return результат
  }

  private static func допустимыйСкаляр(_ скаляр: UInt32) -> Bool {
    скаляр <= 0x10FFFF && !(0xD800...0xDFFF).contains(скаляр)
  }

  private static func повторить(
    _ правила: [ПравилоБайтов], байты: [UInt8], шаг: String,
    счётчик: inout СчётчикИсполнения
  ) throws -> [UInt32] {
    var позиция = 0
    var скаляры: [UInt32] = []
    while позиция < байты.count {
      var выбранное: ПравилоБайтов?
      var достигнуто = позиция
      for правило in правила {
        var совпало = true
        for (смещение, диапазон) in правило.байты.enumerated() {
          try счётчик.операция()
          let адрес = позиция + смещение
          if адрес >= байты.count || !диапазон.содержит(Int(байты[адрес])) {
            достигнуто = max(достигнуто, адрес)
            совпало = false
            break
          }
        }
        if совпало {
          выбранное = правило
          break
        }
      }
      guard let правило = выбранное else {
        throw ОшибкаИсполнения(
          достигнуто == байты.count ? "незавершённый-вход" : "нет-правила",
          "Исходные байты не соответствуют определению", позицияБайта: достигнуто,
          началоПоследовательности: позиция)
      }
      var скаляр: UInt32 = 0
      for поле in правило.поля {
        try счётчик.операция()
        скаляр |= (UInt32(байты[позиция + поле.байт]) & UInt32(поле.маска)) << поле.сдвиг
      }
      guard допустимыйСкаляр(скаляр) else {
        throw ОшибкаИсполнения(
          "скаляр", "Получено значение вне множества Unicode-скаляров",
          позицияБайта: позиция, началоПоследовательности: позиция)
      }
      guard скаляры.count < счётчик.пределы.байтовРезультата / 4 else {
        throw ОшибкаИсполнения("предел-результата", "Скаляры превышают бюджет")
      }
      скаляры.append(скаляр)
      счётчик.записать(
        СледПравилаОператора(
          шаг: шаг, правило: правило.идентификатор,
          позицияБайта: позиция, длина: правило.байты.count, скаляр: скаляр))
      позиция += правило.байты.count
    }
    return скаляры
  }

  private static func изменитьТекст(
    _ текст: String, действие: ДействиеОператора,
    счётчик: inout СчётчикИсполнения
  ) throws -> String {
    let предел = счётчик.пределы.байтовРезультата
    var результат = ""
    func добавить(_ часть: String) throws {
      guard часть.utf8.count <= предел - результат.utf8.count else {
        throw ОшибкаИсполнения("предел-результата", "Текст превышает бюджет")
      }
      результат += часть
    }
    switch действие {
    case .обрезать:
      let часть = текст.trimmingCharacters(in: .whitespacesAndNewlines)
      try добавить(часть)
    case .нижнийРегистр:
      // Unicode lowercasing зависит от контекста всей строки (например, финальная сигма).
      // Максимальный временный объём ограничен конечным входом и таблицами runtime.
      try добавить(текст.lowercased())
    case .сжатьПробелы:
      var нуженПробел = false
      for символ in текст {
        try счётчик.операция()
        if символ.isWhitespace {
          нуженПробел = !результат.isEmpty
        } else {
          if нуженПробел {
            try добавить(" ")
            нуженПробел = false
          }
          try добавить(String(символ))
        }
      }
    case .заменить(let старое, let новое):
      var остаток = текст.startIndex
      while let диапазон = текст.range(of: старое, range: остаток..<текст.endIndex) {
        try счётчик.операция()
        try добавить(String(текст[остаток..<диапазон.lowerBound]))
        try добавить(новое)
        остаток = диапазон.upperBound
      }
      try добавить(String(текст[остаток...]))
    case .префикс(let префикс):
      try добавить(префикс)
      try добавить(текст)
    case .повторитьПравила, .упаковатьСлова:
      throw ОшибкаИсполнения("тип-входа", "Нет текстового оператора")
    }
    return результат
  }
}

import Foundation

/// Формирует строковый литерал Swift без вставки исходных символов пользователя.
enum КодированиеЛитералаSwift {
  static func кодировать(
    _ текст: String, пределИсходныхБайтов: Int, пределJSON: Int, операция: () throws -> Void
  ) throws -> String {
    guard пределИсходныхБайтов >= 2 else {
      throw ОшибкаИсполнения("предел-результата", "Литерал Swift превышает бюджет исходных байтов")
    }
    guard пределJSON >= 6 else {
      throw ОшибкаИсполнения("предел-результата", "JSON-литерал превышает бюджет результата")
    }

    // Пустой литерал `""` занимает 2 байта, его JSON-строка — 6.
    var размерИсходника = 2
    var размерJSON = 6
    for скаляр in текст.unicodeScalars {
      try операция()
      let знаковШестнадцатеричногоЧисла = числоЗнаков(скаляр.value)
      // Экранирование Swift добавляет 4 служебных байта; JSON экранирует его обратную косую.
      let (новыйРазмерИсходника, переполнениеИсходника) = размерИсходника.addingReportingOverflow(
        4 + знаковШестнадцатеричногоЧисла)
      let (новыйРазмерJSON, переполнениеJSON) = размерJSON.addingReportingOverflow(
        5 + знаковШестнадцатеричногоЧисла)
      guard !переполнениеИсходника, !переполнениеJSON else {
        throw ОшибкаИсполнения("переполнение-размера", "Размер литерала Swift или JSON не представим")
      }
      guard новыйРазмерИсходника <= пределИсходныхБайтов else {
        throw ОшибкаИсполнения("предел-результата", "Литерал Swift превышает бюджет исходных байтов")
      }
      guard новыйРазмерJSON <= пределJSON else {
        throw ОшибкаИсполнения("предел-результата", "JSON-литерал превышает бюджет результата")
      }
      размерИсходника = новыйРазмерИсходника
      размерJSON = новыйРазмерJSON
    }

    var результат = String()
    результат.reserveCapacity(размерИсходника)
    результат.append("\"")
    for скаляр in текст.unicodeScalars {
      результат.append(contentsOf: "\\u{")
      результат.append(contentsOf: String(скаляр.value, radix: 16))
      результат.append("}")
    }
    результат.append("\"")
    return результат
  }

  private static func числоЗнаков(_ значение: UInt32) -> Int {
    var остаток = значение
    var знаков = 1
    while остаток >= 16 {
      остаток /= 16
      знаков += 1
    }
    return знаков
  }
}

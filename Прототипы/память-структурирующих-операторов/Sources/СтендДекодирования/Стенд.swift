@inline(never)
func потребить(_ результат: РезультатСравнения) -> UInt64 {
  var сумма: UInt64 = 14695981039346656037
  for скаляр in результат.скаляры { сумма = (сумма ^ UInt64(скаляр)) &* 1099511628211 }
  if let байты = результат.байты {
    for байт in байты { сумма = (сумма ^ UInt64(байт)) &* 1099511628211 }
  }
  return сумма
}

func хэш(_ данные: Data) -> String {
  SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}

@inline(never)
func интерпретировать(
  _ определение: ОпределениеОператора, вход: ЗначениеОператора,
  профиль: ((ЗамерИсполнения) -> Void)? = nil
) throws -> РезультатСравнения {
  let наблюдение = try AutomationExecutor.выполнить(определение, вход: вход, профиль: профиль)
  guard let скаляры = наблюдение.скаляры else { throw ОшибкаСтенда.несоответствие("Нет скаляров") }
  let байты: [UInt8]?
  switch наблюдение.результат {
  case .байты(let значения): байты = значения
  case .скаляры: байты = nil
  case .текст: throw ОшибкаСтенда.несоответствие("Неверный тип результата")
  }
  return РезультатСравнения(скаляры: скаляры, байты: байты, наблюдение: наблюдение)
}

struct ПакетИзмерений {
  let повторов: Int
  let наносекунды: UInt64
  let минимум: UInt64
  let максимум: UInt64
  let полныеНаносекунды: UInt64
  let контрольнаяСумма: UInt64
  var среднее: Double { Double(наносекунды) / Double(повторов) }
  var запись: [String: Any] {
    ["повторов": повторов, "наносекундыВызовов": наносекунды,
     "минимумВызоваНс": минимум, "максимумВызоваНс": максимум,
     "полныеНаносекундыПакета": полныеНаносекунды,
     "среднееВызоваНс": среднее, "контрольнаяСумма": String(контрольнаяСумма)]
  }
}

func измеритьПакет(
  повторов: Int, ожидаемаяСумма: UInt64, вызов: () throws -> РезультатСравнения
) throws -> ПакетИзмерений {
  var сумма: UInt64 = 0
  var длительность: UInt64 = 0
  var минимум = UInt64.max
  var максимум: UInt64 = 0
  let началоПакета = DispatchTime.now().uptimeNanoseconds
  for _ in 0..<повторов {
    try autoreleasepool {
      let начало = DispatchTime.now().uptimeNanoseconds
      let результат = try вызов()
      let время = DispatchTime.now().uptimeNanoseconds - начало
      длительность += время
      минимум = min(минимум, время)
      максимум = max(максимум, время)
      // Обход всего результата и освобождение происходят после второго таймера.
      let текущаяСумма = потребить(результат)
      guard текущаяСумма == ожидаемаяСумма else {
        throw ОшибкаСтенда.несоответствие("Изменился результат измеряемого вызова")
      }
      сумма &+= текущаяСумма
    }
  }
  return ПакетИзмерений(
    повторов: повторов, наносекунды: длительность, минимум: минимум, максимум: максимум,
    полныеНаносекунды: DispatchTime.now().uptimeNanoseconds - началоПакета,
    контрольнаяСумма: сумма)
}

func числоПовторов(_ наносекунды: Double) -> Int {
  min(10000, max(1, Int(ceil(20_000_000 / max(1, наносекунды)))))
}

func статистика(_ значения: [Double], байтов: Int) -> [String: Any] {
  let ряд = значения.sorted()
  let медиана = ряд[ряд.count / 2]
  let отклонения = ряд.map { abs($0 - медиана) }.sorted()
  return ["медианаНс": медиана, "минимумНс": ряд.first!, "максимумНс": ряд.last!,
          "медианноеАбсолютноеОтклонениеНс": отклонения[ряд.count / 2],
          "МБвСекунду": Double(байтов) * 1000 / медиана]
}

public enum СтендДекодирования {
  public static func выполнить(измерять: Bool) throws -> Data {
    #if DEBUG
    guard !измерять else { throw ОшибкаСтенда.несоответствие("Для измерения нужна сборка Release") }
    #endif
    let начало = DispatchTime.now().uptimeNanoseconds
    let времяНачала = ISO8601DateFormatter().string(from: Date())
    let загрузка = DispatchTime.now().uptimeNanoseconds
    let данныеОпределения = try РесурсыОпределений.прочитать("UTF-8-в-UTF-32LE")
    let времяЗагрузки = DispatchTime.now().uptimeNanoseconds - загрузка
    let разбор = DispatchTime.now().uptimeNanoseconds
    let упакованное = try ОпределениеОператора.разобрать(данныеОпределения)
    guard упакованное.шаги.count == 2,
          упакованное.шаги.last?.действие == .упаковатьСлова(ширина: 4, порядок: .младшийПервым)
    else { throw ОшибкаСтенда.несоответствие("Изменилось исходное определение") }
    let безУпаковки = ОпределениеОператора(
      идентификатор: упакованное.идентификатор, версия: упакованное.версия,
      правила: упакованное.правила, шаги: Array(упакованное.шаги.dropLast()))
    let времяРазбора = DispatchTime.now().uptimeNanoseconds - разбор
    let корпус = корпусСравнения()
    var положительные: [[String: Any]] = []
    var ошибочные: [[String: Any]] = []
    var наблюдения: [[String: Any]] = []
    var калибровки: [[String: Any]] = []
    var профили: [[String: Any]] = []
    var итоги: [[String: Any]] = []
    let началоКорректности = DispatchTime.now().uptimeNanoseconds
    for пример in короткиеВходы() + корпус {
      for упаковка in [false, true] {
        let определение = упаковка ? упакованное : безУпаковки
        let результаты = [стандартноДекодировать(пример.байты, упаковать: упаковка),
          try интерпретировать(определение, вход: .байты(пример.байты))]
        for результат in результаты {
          guard let результат, результат.скаляры == пример.скаляры,
            результат.байты == (упаковка ? пример.ожидаемыеБайты : nil)
          else { throw ОшибкаСтенда.несоответствие(пример.имя) }
        }
        положительные.append(["вход": пример.имя, "упаковкаLE": упаковка,
          "байтовВхода": пример.байты.count, "скаляров": пример.скаляры.count,
          "байтовUTF32": пример.ожидаемыеБайты.count, "хэшВхода": хэш(Data(пример.байты)),
          "хэшОжидаемыхБайтовLE": хэш(Data(пример.ожидаемыеБайты)), "совпадает": true])
      }
    }
    let неверные: [[UInt8]] = [[0x80], [0xC0, 0xAF], [0xC2, 0x41], [0xED, 0xA0, 0x80],
      [0xF4, 0x90, 0x80, 0x80], [0xE2, 0x82], [0x41, 0xF0, 0x9F]]
    for байты in неверные {
      for упаковка in [false, true] {
        guard стандартноДекодировать(байты, упаковать: упаковка) == nil else {
          throw ОшибкаСтенда.несоответствие("Swift принял неверный вход")
        }
        do {
          _ = try интерпретировать(упаковка ? упакованное : безУпаковки, вход: .байты(байты))
          throw ОшибкаСтенда.несоответствие("Интерпретатор принял неверный вход")
        } catch let ошибка as ОшибкаИсполнения {
          ошибочные.append(["байты": байты, "упаковкаLE": упаковка,
            "стандартныйИсход": "nil; префикс отброшен", "кодИнтерпретатора": ошибка.код,
            "позицияБайта": ошибка.позицияБайта as Any? ?? NSNull(),
            "началоПоследовательности": ошибка.началоПоследовательности as Any? ?? NSNull()])
        }
      }
    }
    let времяКорректности = DispatchTime.now().uptimeNanoseconds - началоКорректности
    let состояниеДо = ProcessInfo.processInfo.thermalState.rawValue
    let началоИзмерений = DispatchTime.now().uptimeNanoseconds
    if измерять {
      for (номерВхода, пример) in корпус.enumerated() {
        for упаковка in [false, true] {
          let определение = упаковка ? упакованное : безУпаковки
          let готовыйВход = ЗначениеОператора.байты(пример.байты)
          let ожидаемаяСумма = потребить(РезультатСравнения(
            скаляры: пример.скаляры, байты: упаковка ? пример.ожидаемыеБайты : nil, наблюдение: nil))
          let пути: [(String, () throws -> РезультатСравнения)] = [
            ("Swift", { стандартноДекодировать(пример.байты, упаковать: упаковка)! }),
            ("интерпретатор", { try интерпретировать(определение, вход: готовыйВход) })]
          var повторы: [Int] = []
          for (имя, вызов) in пути {
            _ = try измеритьПакет(повторов: 3, ожидаемаяСумма: ожидаемаяСумма, вызов: вызов)
            let проба = try измеритьПакет(повторов: 1, ожидаемаяСумма: ожидаемаяСумма, вызов: вызов)
            let количество = числоПовторов(проба.среднее)
            let калибровка = try измеритьПакет(
              повторов: количество, ожидаемаяСумма: ожидаемаяСумма, вызов: вызов)
            повторы.append(числоПовторов(калибровка.среднее))
            калибровки.append(["вход": пример.имя, "упаковкаLE": упаковка, "путь": имя,
              "проба": проба.запись, "пакет": калибровка.запись, "выбраноПовторов": повторы.last!])
          }
          var ряды: [[Double]] = [[], []]
          for серия in 0..<9 {
            let порядок = (серия + номерВхода + (упаковка ? 1 : 0)) % 2 == 0 ? [0, 1] : [1, 0]
            for (позиция, индекс) in порядок.enumerated() {
              let пакет = try измеритьПакет(
                повторов: повторы[индекс], ожидаемаяСумма: ожидаемаяСумма, вызов: пути[индекс].1)
              ряды[индекс].append(пакет.среднее)
              var запись = пакет.запись
              запись.merge(["вход": пример.имя, "упаковкаLE": упаковка,
                "серия": серия + 1, "позицияВПаре": позиция + 1, "путь": пути[индекс].0,
                "тепловоеСостояние": ProcessInfo.processInfo.thermalState.rawValue]) { _, новое in новое }
              наблюдения.append(запись)
            }
          }
          let стандарт = статистика(ряды[0], байтов: пример.байты.count)
          let интерпретатор = статистика(ряды[1], байтов: пример.байты.count)
          итоги.append(["вход": пример.имя, "упаковкаLE": упаковка,
            "байтовВхода": пример.байты.count, "скаляров": пример.скаляры.count,
            "Swift": стандарт, "интерпретатор": интерпретатор,
            "отношениеВремён": (интерпретатор["медианаНс"] as! Double) / (стандарт["медианаНс"] as! Double)])
          // Отдельные диагностические вызовы с callback не входят в основные ряды.
          for повтор in 1...3 {
            var метки: [[String: Any]] = []
            let началоПрофиля = DispatchTime.now().uptimeNanoseconds
            let результат = try интерпретировать(определение, вход: готовыйВход) { метка in
              метки.append(["стадия": метка.стадия, "наносекунды": метка.наносекунды, "исход": метка.исход])
            }
            let полное = DispatchTime.now().uptimeNanoseconds - началоПрофиля
            guard потребить(результат) == ожидаемаяСумма else { throw ОшибкаСтенда.несоответствие("Профиль") }
            профили.append(["вход": пример.имя, "упаковкаLE": упаковка, "повтор": повтор,
              "полныйВызовНс": полное, "метки": метки,
              "записейТрассы": результат.наблюдение!.трасса.count,
              "пропущеноЗаписей": результат.наблюдение!.пропущеноЗаписей,
              "хэшНаблюдения": результат.наблюдение!.хэшНаблюдения])
          }
        }
      }
    }
    let отчёт: [String: Any] = [
      "схема": "fum.сравнение-декодирования.1", "началоUTC": времяНачала,
      "измерение": измерять, "положительные": положительные, "ошибочные": ошибочные,
      "наблюдения": наблюдения, "калибровки": калибровки, "профили": профили, "итоги": итоги,
      "подготовка": ["загрузкаНс": времяЗагрузки, "разборИПодготовкаОпределенийНс": времяРазбора,
        "корректностьНс": времяКорректности, "хэшJSONОпределения": хэш(данныеОпределения),
        "хэшОпределенияСкаляров": хэш(try безУпаковки.данные())],
      "условия": ["ОС": ProcessInfo.processInfo.operatingSystemVersionString,
        "логическихПроцессоров": ProcessInfo.processInfo.processorCount,
        "памятиБайт": ProcessInfo.processInfo.physicalMemory,
        "тепловоеСостояниеДо": состояниеДо, "тепловоеСостояниеПосле": ProcessInfo.processInfo.thermalState.rawValue,
        "энергосбережение": ProcessInfo.processInfo.isLowPowerModeEnabled,
        "серий": 9, "прогревов": 3, "цельПакетаНс": 20_000_000,
        "минимумПовторов": 1, "максимумПовторов": 10000,
        "лимитВходаБайт": 262144, "лимитВыходаБайт": 1048576, "лимитТрассы": 256],
      "измеренияВсегоНс": DispatchTime.now().uptimeNanoseconds - началоИзмерений,
      "стендВсегоНс": DispatchTime.now().uptimeNanoseconds - начало,
      "граница": "Полный готовый API и материализация результата. JSON и входы заранее. Таймеры на каждом вызове; контрольная сумма, освобождение и autoreleasepool снаружи. Профиль с callback отдельно. Внутреннее исполнение не является чистым декодером. Ошибки только проверены, не измерены."
    ]
    return try JSONSerialization.data(withJSONObject: отчёт, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes])
  }
}

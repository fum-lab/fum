struct РезультатСравнения {
  let скаляры: [UInt32]
  let байты: [UInt8]?
  let наблюдение: НаблюдениеОператора?
}

@inline(never)
func стандартноДекодировать(_ байты: [UInt8], упаковать: Bool) -> РезультатСравнения? {
  var скаляры: [UInt32] = []
  let ошибка = transcode(
    байты.makeIterator(), from: Unicode.UTF8.self, to: Unicode.UTF32.self,
    stoppingOnError: true, into: { скаляры.append($0) })
  guard !ошибка else { return nil }
  var выход: [UInt8]?
  if упаковать {
    var буфер: [UInt8] = []
    буфер.reserveCapacity(скаляры.count * 4)
    for скаляр in скаляры {
      for сдвиг in stride(from: 0, to: 32, by: 8) {
        буфер.append(UInt8(truncatingIfNeeded: скаляр >> сдвиг))
      }
    }
    выход = буфер
  }
  return РезультатСравнения(скаляры: скаляры, байты: выход, наблюдение: nil)
}

enum ОшибкаСтенда: Error { case несоответствие(String) }

struct ВходСравнения {
  let имя: String
  let байты: [UInt8]
  let скаляры: [UInt32]
  let ожидаемыеБайты: [UInt8]

  init(_ имя: String, _ байты: [UInt8], _ скаляры: [UInt32], повторов: Int = 1) {
    self.имя = имя
    self.байты = Array(repeating: байты, count: повторов).flatMap { $0 }
    self.скаляры = Array(repeating: скаляры, count: повторов).flatMap { $0 }
    // Независимый арифметический оракул упаковки; скаляры заданы литералами.
    self.ожидаемыеБайты = self.скаляры.flatMap { скаляр in
      [UInt8(скаляр % 256), UInt8((скаляр / 256) % 256),
       UInt8((скаляр / 65536) % 256), UInt8(скаляр / 16777216)]
    }
  }
}

func корпусСравнения() -> [ВходСравнения] {
  let образцы: [(String, [UInt8], [UInt32])] = [
    ("ASCII", [0x41, 0x7A, 0x20, 0x0A], [0x41, 0x7A, 0x20, 0x0A]),
    ("кириллица", [0xD0, 0x81, 0xD0, 0xB6, 0x20, 0xD1, 0x91, 0xD0, 0xB6, 0x2E],
      [0x401, 0x436, 0x20, 0x451, 0x436, 0x2E]),
    ("смесь", [0x41, 0xD1, 0x91, 0xE2, 0x82, 0xAC, 0xF0, 0x9F, 0x99, 0x82],
      [0x41, 0x451, 0x20AC, 0x1F642]),
    ("декомпозиция", [0x65, 0xCC, 0x81, 0, 0xEF, 0xBB, 0xBF, 0xF0, 0x9F, 0x99, 0x82],
      [0x65, 0x301, 0, 0xFEFF, 0x1F642]),
  ]
  return образцы.flatMap { имя, байты, скаляры in
    [4096, 32768, 262144].map { предел in
      ВходСравнения("\(имя)-\(предел)", байты, скаляры, повторов: предел / байты.count)
    }
  }
}


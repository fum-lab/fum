def требовать(условие, пояснение):
    if not условие:
        raise ValueError(пояснение)


def близко(первое, второе):
    return math.isclose(первое, второе, rel_tol=1e-12, abs_tol=1e-6)


def проверить(данные, прототип):
    требовать(данные["схема"] == "fum.сравнение-декодирования.1" and данные["измерение"] is True, "Нужен измеренный профиль")
    требовать(len(данные["наблюдения"]) == 432 and len(данные["итоги"]) == 24, "Потеря наблюдений")
    требовать(len(данные["профили"]) == 72 and len(данные["калибровки"]) == 48, "Потеря диагностики")
    требовать(set(данные["происхождение"]["исходники"]) == ОБЯЗАТЕЛЬНЫЕ_ИСХОДНИКИ, "Неполный или лишний состав квитанции")
    фактические = {"Package.swift", "Проверки/сравнить-декодирование.py"}
    for каталог in ("Sources", "Tests"):
        фактические.update(str(путь.relative_to(прототип)) for путь in (прототип / каталог).rglob("*") if путь.is_file())
    требовать(фактические == ОБЯЗАТЕЛЬНЫЕ_ИСХОДНИКИ, "Неполный или лишний состав исходников")
    for имя, ожидаемый in данные["происхождение"]["исходники"].items():
        путь = (прототип / имя).resolve()
        требовать(путь.is_relative_to(прототип.resolve()), "Неверный путь исходника")
        требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == ожидаемый, f"Изменён исходник: {имя}")
    группы = defaultdict(list)
    пары = defaultdict(list)
    for запись in данные["наблюдения"]:
        требовать(1 <= запись["повторов"] <= 10000, "Неверное число повторов")
        требовать(близко(запись["среднееВызоваНс"], запись["наносекундыВызовов"] / запись["повторов"]), "Среднее пакета")
        требовать(0 < запись["минимумВызоваНс"] <= запись["среднееВызоваНс"] <= запись["максимумВызоваНс"], "Границы пакета")
        требовать(запись["полныеНаносекундыПакета"] >= запись["наносекундыВызовов"], "Вложенность времени")
        ключ = (запись["вход"], запись["упаковкаLE"])
        группы[ключ + (запись["путь"],)].append(запись)
        пары[ключ + (запись["серия"],)].append(запись)
    for ключ, ряд in пары.items():
        требовать(len(ряд) == 2 and {запись["путь"] for запись in ряд} == {"Swift", "интерпретатор"}, "Пара путей")
        требовать([запись["позицияВПаре"] for запись in ряд] == [1, 2], "Порядок внутри пары")
        if ключ[-1] > 1:
            требовать(пары[ключ[:-1] + (ключ[-1] - 1,)][0]["путь"] != ряд[0]["путь"], "Нет чередования")
    ключиИтогов = [(итог["вход"], итог["упаковкаLE"]) for итог in данные["итоги"]]
    требовать(len(set(ключиИтогов)) == len(ключиИтогов), "Повтор итога")
    требовать(len(группы) == 48 and set(ключиИтогов) == {ключ[:2] for ключ in группы}, "Неполное покрытие рядов итогами")
    for итог in данные["итоги"]:
        for путь in ("Swift", "интерпретатор"):
            ряд = группы[(итог["вход"], итог["упаковкаLE"], путь)]
            требовать(sorted(запись["серия"] for запись in ряд) == list(range(1, 10)), "Девять уникальных серий")
            значения = [запись["наносекундыВызовов"] / запись["повторов"] for запись in ряд]
            медиана = statistics.median(значения)
            ожидаемые = {"медианаНс": медиана, "минимумНс": min(значения), "максимумНс": max(значения),
                         "медианноеАбсолютноеОтклонениеНс": statistics.median(abs(значение - медиана) for значение in значения),
                         "МБвСекунду": итог["байтовВхода"] * 1000 / медиана}
            for имя, значение in ожидаемые.items():
                требовать(близко(итог[путь][имя], значение), f"Статистика: {имя}")
        требовать(близко(итог["отношениеВремён"], итог["интерпретатор"]["медианаНс"] / итог["Swift"]["медианаНс"]), "Отношение времён")


def таблица(данные):
    строки = [["Вход", "Байт / скаляров", "Результат", "Swift, мс", "Интерпретатор, мс", "Отношение", "МБ/с Swift / интерпретатор"]]
    for итог in данные["итоги"]:
        стандарт, интерпретатор = итог["Swift"], итог["интерпретатор"]
        строки.append([итог["вход"], f"{итог['байтовВхода']} / {итог['скаляров']}",
                       "скаляры + LE" if итог["упаковкаLE"] else "скаляры",
                       f"{стандарт['медианаНс'] / 1e6:.4f}", f"{интерпретатор['медианаНс'] / 1e6:.4f}",
                       f"{итог['отношениеВремён']:.2f}×", f"{стандарт['МБвСекунду']:.2f} / {интерпретатор['МБвСекунду']:.2f}"])
    ширины = [max(len(строка[номер]) for строка in строки) for номер in range(len(строки[0]))]
    строки.insert(1, ["-" * ширина for ширина in ширины])
    return "\n".join("| " + " | ".join(поле.ljust(ширина) for поле, ширина in zip(строка, ширины)) + " |" for строка in строки)


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("вход", type=Path)
    разбор.add_argument("--таблица", type=Path)
    разбор.add_argument("--профиль", type=Path)
    разбор.add_argument("--корень-исходников", type=Path, help="Точный восстановленный снимок; по умолчанию текущий прототип")
    параметры = разбор.parse_args()
    данные = json.loads(параметры.вход.read_text())
    прототип = (параметры.корень_исходников or Path(__file__).resolve().parents[1]).resolve()
    времена = []
    for _ in range(5):
        начало = time.perf_counter_ns()
        проверить(данные, прототип)
        времена.append(time.perf_counter_ns() - начало)
    if параметры.таблица:
        параметры.таблица.write_text(таблица(данные) + "\n")
    if параметры.профиль:
        параметры.профиль.write_text(json.dumps({"схема": "fum.проверка-сравнения.1", "наносекунды": времена,
            "хэшПрофиля": hashlib.sha256(параметры.вход.read_bytes()).hexdigest(),
            "хэшПроверяющего": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "вывод": "Все 432 пакета, 24 итога и хэши исходников согласованы; оптимизация малого проверяющего не требуется"}, ensure_ascii=False, indent=2) + "\n")
    print("Пересчитаны 432 пакета и 24 уникальных итога; проверен полный состав исходников и их хэши. Для диагностических профилей проверено только количество 72.")


if __name__ == "__main__":
    главная()

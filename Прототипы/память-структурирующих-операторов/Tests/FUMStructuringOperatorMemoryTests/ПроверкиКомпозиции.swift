      }
    }
  }

  func test_ВерсияДваУчитываетБайтыПравилВОбщейТрассе() throws {
    let правило = ПравилоБайтов(
      идентификатор: "байт", байты: [.init(от: 0, до: 127)],
      поля: [.init(байт: 0, маска: 127, сдвиг: 0)])
    var определение = ОпределениеОператора(
      идентификатор: "трасса", версия: 1, правила: [правило],
      шаги: [.init(идентификатор: "читать", действие: .повторитьПравила(["байт"]))])
    определение.схема = "fum.определение-оператора.2"
    let краткое = try AutomationExecutor.выполнить(
      определение, вход: .байты([65, 66]),
      пределы: .init(байтовРезультата: 32))
    XCTAssertEqual(краткое.результат, .скаляры([65, 66]))
    XCTAssertTrue(краткое.трасса.isEmpty)
    XCTAssertEqual(краткое.пропущеноЗаписей, 2)
    определение.схема = "fum.определение-оператора.1"
    XCTAssertEqual(
      try AutomationExecutor.выполнить(
        определение, вход: .байты([65, 66]),
        пределы: .init(байтовРезультата: 32)
      ).трасса.count, 2)
  }

  func test_ВложенныйРезультатНеОграниченПределомИсходногоJSON() throws {
    let определение = try сРезультатом(вызов("удвоение", 1, ["переменная", "вход"])) { объект in
      var определения = объект["определения"] as! [[String: Any]]
      определения[0]["вход"] = "строка"
      определения[0]["выход"] = "строка"
      var граф = определения[0]["граф"] as! [String: Any]
      граф["результат"] = [
        "соединить", ["переменная", "вход"], ["переменная", "вход"],
        ["переменная", "вход"], ["переменная", "вход"],
      ]
      определения[0]["граф"] = граф
      // Пара не используется, но объявляет строгую несовместимость лишь во время вызова.
      объект["определения"] = определения
    }
    let вход = "\"" + String(repeating: "A", count: 70_000) + "\""
    let наблюдение = try AutomationExecutor.выполнить(определение, вход: .текст(вход))
    XCTAssertEqual(наблюдение.результат.размер, 280_002)
  }

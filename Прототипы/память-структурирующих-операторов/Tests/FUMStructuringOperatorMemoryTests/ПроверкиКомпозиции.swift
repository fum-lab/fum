import Foundation
import XCTest

@testable import FUMStructuringOperatorMemory

final class ПроверкиКомпозиции: XCTestCase {
  let корень = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    .deletingLastPathComponent().deletingLastPathComponent()
  func данные() throws -> Data {
    let корень = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
      .deletingLastPathComponent().deletingLastPathComponent()
    return try Data(
      contentsOf: корень.appendingPathComponent("Проверки/композиция/определение.json"))
  }

  func test_ВнешнийОператорПрименяетПаруИТройноеУдвоение() throws {
    let определение = try ОпределениеОператора.разобрать(данные())
    let наблюдение = try AutomationExecutor.выполнить(определение, вход: .текст("{}"))
    XCTAssertEqual(наблюдение.результат, .текст(#"{"пара":[6,8],"три":[2,4,6]}"#))
    XCTAssertEqual(наблюдение, try AutomationExecutor.выполнить(определение, вход: .текст("{}")))
    XCTAssertEqual(наблюдение.схема, "fum.наблюдение-оператора.2")
    XCTAssertEqual(наблюдение.схемаТрассы, "fum.трасса-применений.1")
    let следы = try XCTUnwrap(наблюдение.применения)
    XCTAssertEqual(следы.map(\.экземпляр), [2, 3, 1, 4, 5, 6])
    XCTAssertEqual(следы.map(\.родитель), [1, 1, nil, nil, nil, nil])
    XCTAssertEqual(следы.map(\.результатJSON), ["6", "8", "[6,8]", "2", "4", "6"])
    XCTAssertEqual(следы.map(\.версия), Array(repeating: 1, count: 6))
    XCTAssertEqual(следы[0].входJSON, "3")
    XCTAssertEqual(следы[0].место, "левое")
    XCTAssertEqual(следы[0].шаг, "расчёт")
    XCTAssertEqual(следы[0].определение, "удвоение")
  }

  func программа(_ изменить: (inout [String: Any]) throws -> Void) throws -> ОпределениеОператора {
    var объект = try XCTUnwrap(JSONSerialization.jsonObject(with: данные()) as? [String: Any])
    try изменить(&объект)
    return try ОпределениеОператора.разобрать(JSONSerialization.data(withJSONObject: объект))
  }

  func сРезультатом(_ выражение: Any, _ изменить: (inout [String: Any]) -> Void = { _ in }) throws
    -> ОпределениеОператора
  {
    try программа { объект in
      объект["шаги"] = [
        [
          "идентификатор": "расчёт", "оператор": "вычислить-JSON",
          "аргументы": [
            "граф": [
              "схема": "fuma.граф-JSON.2", "числа": "целые64-без-дробей",
              "переменные": [], "результат": выражение,
            ]
          ],
        ]
      ]
      изменить(&объект)
    }
  }

  func вызов(_ имя: String = "удвоение", _ версия: Int = 1, _ вход: Any = 7) -> [Any] {
    ["вызвать", "место", имя, версия, вход]
  }

  func ошибка(_ код: String, _ действие: () throws -> Void) {
    XCTAssertThrowsError(try действие()) { XCTAssertEqual(($0 as? ОшибкаИсполнения)?.код, код) }
  }

  func test_НетОпределенияИНеизвестнаяВерсияДажеВЛенивойВетви() throws {
    ошибка("нет-определения") { _ = try сРезультатом(вызов("нет")) }
    ошибка("версия-определения") { _ = try сРезультатом(вызов("удвоение", 2)) }
    ошибка("нет-определения") {
      _ = try сРезультатом(["если", ["истина"], 1, вызов("нет")])
    }
  }

  func test_ПрямыеИКосвенныеЦиклыИКоллизияКорня() throws {
    for имя in ["удвоение", "пара", "внешний"] {
      ошибка("цикл-определений") {
        _ = try программа { объект in
          var определения = объект["определения"] as! [[String: Any]]
          var граф = определения[0]["граф"] as! [String: Any]
          граф["результат"] = вызов(имя)
          определения[0]["граф"] = граф
          объект["определения"] = определения
        }
      }
    }
    ошибка("цикл-определений") { _ = try сРезультатом(вызов("внешний")) }
    ошибка("повтор-определения") {
      _ = try программа { объект in
        var определения = объект["определения"] as! [[String: Any]]
        определения.append(определения[0])
        объект["определения"] = определения
      }
    }
    ошибка("повтор-определения") {
      _ = try программа { объект in
        var определения = объект["определения"] as! [[String: Any]]
        определения[0]["идентификатор"] = "внешний"
        объект["определения"] = определения
      }
    }
  }

  func test_ВходИВыходСтрогоПроверяются() throws {
    let вход = try сРезультатом(вызов("удвоение", 1, "семь"))
    ошибка("тип-входа-определения") {
      _ = try AutomationExecutor.выполнить(вход, вход: .текст("{}"))
    }
    let выход = try сРезультатом(вызов()) { объект in
      var определения = объект["определения"] as! [[String: Any]]
      определения[0]["выход"] = "строка"
      объект["определения"] = определения
    }
    ошибка("тип-выхода-определения") {
      _ = try AutomationExecutor.выполнить(выход, вход: .текст("{}"))
    }
  }

  func test_ВсеВложенныеВызовыРасходуютОбщийБюджет() throws {
    let определение = try ОпределениеОператора.разобрать(данные())
    let полное = try AutomationExecutor.выполнить(определение, вход: .текст("{}"))
    ошибка("предел-операций") {
      _ = try AutomationExecutor.выполнить(
        определение, вход: .текст("{}"),
        пределы: .init(операций: полное.выполненоОпераций - 1))
    }
    XCTAssertEqual(
      полное,
      try AutomationExecutor.выполнить(
        определение, вход: .текст("{}"),
        пределы: .init(операций: полное.выполненоОпераций)))
    XCTAssertGreaterThan(полное.выполненоОпераций, 6)
  }

  func test_ПовторМестаВОтображенииИОграничениеТрассы() throws {
    let определение = try сРезультатом([
      "отобразить", ["массив", 1, 2, 3], "число",
      вызов("удвоение", 1, ["переменная", "число"]),
    ])
    let наблюдение = try AutomationExecutor.выполнить(определение, вход: .текст("{}"))
    XCTAssertEqual(наблюдение.результат, .текст("[2,4,6]"))
    XCTAssertEqual(наблюдение.применения?.map(\.экземпляр), [1, 2, 3])
    XCTAssertEqual(наблюдение.применения?.map(\.место), ["место", "место", "место"])
    let короткое = try AutomationExecutor.выполнить(
      определение, вход: .текст("{}"),
      пределы: .init(записейТрассы: 1))
    XCTAssertEqual(короткое.результат, наблюдение.результат)
    XCTAssertEqual(короткое.применения?.count, 1)
    XCTAssertEqual(короткое.пропущеноПрименений, 2)
    let поБайтам = try AutomationExecutor.выполнить(
      определение, вход: .текст("{}"),
      пределы: .init(байтовРезультата: 32))
    XCTAssertEqual(поБайтам.применения?.count, 0)
    XCTAssertEqual(поБайтам.пропущеноПрименений, 3)
  }

  func test_РезультатРавенЯвномуРазвёртыванию() throws {
    let композиция = try AutomationExecutor.выполнить(
      ОпределениеОператора.разобрать(данные()), вход: .текст("{}"))
    let развёрнутое = try сРезультатом([
      "пара": ["массив", ["умножить", 3, 2], ["умножить", 4, 2]],
      "три": ["массив", ["умножить", 1, 2], ["умножить", 2, 2], ["умножить", 3, 2]],
    ])
    XCTAssertEqual(
      композиция.результат,
      try AutomationExecutor.выполнить(развёрнутое, вход: .текст("{}")).результат)
  }

  func test_ВерсияОдинСохраняетПолноеНаблюдениеПрежнегоБинарника() throws {
    let запись = try XCTUnwrap(
      JSONSerialization.jsonObject(
        with: Data(
          contentsOf:
            корень.appendingPathComponent("Проверки/композиция/запись-v1.json"))) as? [String: Any])
    let принятые = try XCTUnwrap(запись["принятыеДанные"] as? [String: Any])
    let определение = try XCTUnwrap(Data(base64Encoded: принятые["исходноеОпределение"] as! String))
    let вход = try XCTUnwrap(
      String(data: Data(base64Encoded: принятые["вход"] as! String)!, encoding: .utf8))
    let наблюдение = try AutomationExecutor.выполнить(
      ОпределениеОператора.разобрать(определение), вход: .текст(вход))
    XCTAssertEqual(
      наблюдение.хэшНаблюдения,
      "sha256:b220e79abaa1ff5d92452b2dc71fa08b0ce3756edca373214911ed9fb04a0e81")
    let новое =
      try JSONSerialization.jsonObject(with: каноническиеДанные(наблюдение)) as! NSDictionary
    XCTAssertEqual(новое, запись["наблюдение"] as! NSDictionary)
    XCTAssertNil(наблюдение.применения)
    ошибка("определение") {
      _ = try программа { объект in
        объект["схема"] = "fum.определение-оператора.1"
        объект.removeValue(forKey: "определения")
      }
    }
  }

  func test_ИдентичностьСодержитТочныеБайтыИВерсию() throws {
    let определение = try сРезультатом([
      "массив", вызов("й", 1, 7), вызов("и\u{306}", 1, 8), вызов("й", 2, 9),
    ]) { объект in
      let исходное = (объект["определения"] as! [[String: Any]])[0]
      var первая = исходное
      var вторая = исходное
      var третья = исходное
      первая["идентификатор"] = "й"
      вторая["идентификатор"] = "и\u{306}"
      третья["идентификатор"] = "й"
      третья["версия"] = 2
      var граф = третья["граф"] as! [String: Any]
      граф["результат"] = ["умножить", ["переменная", "вход"], 3]
      третья["граф"] = граф
      объект["определения"] = [первая, вторая, третья]
    }
    let наблюдение = try AutomationExecutor.выполнить(определение, вход: .текст("{}"))
    XCTAssertEqual(наблюдение.результат, .текст("[14,16,27]"))
    XCTAssertEqual(
      наблюдение.применения?.map { Data($0.определение.utf8) },
      [Data("й".utf8), Data("и\u{306}".utf8), Data("й".utf8)])
    XCTAssertEqual(наблюдение.применения?.map(\.версия), [1, 1, 2])
    let байты = try каноническиеДанные(определение.представление)
    XCTAssertEqual(
      байты, try каноническиеДанные(ОпределениеОператора.разобрать(байты).представление))
  }


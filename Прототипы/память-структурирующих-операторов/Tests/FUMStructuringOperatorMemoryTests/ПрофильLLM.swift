private func измеритьКэшПрофиляLLM(повтор: Int) async throws {
  let тело = Data(
    #"{"id":"fixture-profile","status":"completed","model":"fixture-observed-model","output":[{"type":"message","role":"assistant","content":[{"type":"output_text","text":"Профиль Ё 🧠"}]}],"usage":{"input_tokens":2,"output_tokens":3,"total_tokens":5}}"#
      .utf8
  )
  let входSHA256 = хэшПрофиляLLM(тело)
  let намерение = try ВызовLLM.сформировать(
    ЗапросLLM(
      идентификатор: "профиль-кэша-llm", поставщик: .опенай,
      запрошеннаяМодель: "fixture-requested-model",
      сообщения: [.init(текст: "Профиль Ё 🧠")],
      секрет: СсылкаНаСекретLLM("профиль-фиктивного-секрета")
    )
  )
  let транспорт = ТранспортПрофиляLLM(тело: тело)
  let первыйИсполнитель = ИсполнительLLM(транспорт: транспорт)
  let часы = ContinuousClock()

  let началоПервого = часы.now
  let перваяЗапись = try await первыйИсполнитель.исполнить(намерение)
  let первоеИсполнение = началоПервого.duration(to: часы.now)

  // Roundtrip в памяти не объявляется устойчивым файловым сохранением.
  let сериализованная = try JSONEncoder().encode(перваяЗапись)
  let сохранённая = try JSONDecoder().decode(ЗаписьВызоваLLM.self, from: сериализованная)
  let новыйИсполнитель = ИсполнительLLM(транспорт: транспорт)
  let началоВосстановления = часы.now
  let восстановленная = try await новыйИсполнитель.восстановить(сохранённая)
  let восстановление = началоВосстановления.duration(to: часы.now)

  var всеРавны = true
  var числоПовторов = 0
  let началоПовторов = часы.now
  for _ in 0..<1000 {
    let повтор = try await новыйИсполнитель.исполнить(намерение)
    // Сравнение выполняется в каждом повторе, даже после возможного расхождения.
    всеРавны = (повтор == перваяЗапись) && всеРавны
    числоПовторов += 1
  }
  let повторы = началоПовторов.duration(to: часы.now)
  let числоОтправок = await транспорт.числоОтправок
  let запросы = await транспорт.запросы
  let инварианты =
    перваяЗапись.ошибка == nil
    && перваяЗапись.исходОтправки == .ответПолучен
    && перваяЗапись.сырыеБайтыОтвета == тело
    && перваяЗапись.хэшСырогоОтвета == входSHA256
    && перваяЗапись.ответ?.текст == "Профиль Ё 🧠"
    && перваяЗапись.ответ?.наблюдаемаяМодель == "fixture-observed-model"
    && перваяЗапись.предложения == nil
    && сохранённая == перваяЗапись
    && восстановленная == перваяЗапись
    && всеРавны
    && числоПовторов == 1000
    && числоОтправок == 1
    && запросы == [намерение.запросHTTP]

  try напечататьПрофильLLM(
    ИзмерениеКэшаПрофиляLLM(
      повтор: повтор, байтовВхода: тело.count, входSHA256: входSHA256,
      телоЗапросаSHA256: хэшПрофиляLLM(намерение.запросHTTP.тело),
      первоеИсполнениеНс: наносекундыПрофиляLLM(первоеИсполнение),
      восстановлениеНс: наносекундыПрофиляLLM(восстановление),
      повторыНс: наносекундыПрофиляLLM(повторы),
      числоПовторов: числоПовторов, числоОтправок: числоОтправок,
      инвариантыВыполнены: инварианты
    )
  )
  #expect(инварианты)
}

private actor ТранспортПрофиляLLM: ТранспортLLM {
  private let тело: Data
  private(set) var числоОтправок = 0
  private(set) var запросы: [HTTPЗапросLLM] = []

  init(тело: Data) { self.тело = тело }

  func отправить(
    _ запрос: HTTPЗапросLLM,
    приём: @Sendable (ЧастьHTTPОтветаLLM) async throws -> Void
  ) async throws {
    try Task.checkCancellation()
    числоОтправок += 1
    запросы.append(запрос)
    try await приём(
      .заголовки(.init(статус: 200, заголовки: ["content-type": "application/json"]))
    )
    try await приём(.данные(тело))
  }
}

private func хэшПрофиляLLM(_ данные: Data) -> String {
  "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}

private func наносекундыПрофиляLLM(_ длительность: Duration) -> Int64 {
  let части = длительность.components
  return части.seconds * 1_000_000_000 + части.attoseconds / 1_000_000_000
}

private func напечататьПрофильLLM<Запись: Encodable>(_ запись: Запись) throws {
  let кодировщик = JSONEncoder()
  кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
  let данные = try кодировщик.encode(запись)
  print(String(decoding: данные, as: UTF8.self))
}

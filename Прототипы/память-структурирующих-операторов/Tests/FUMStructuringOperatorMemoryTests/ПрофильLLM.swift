/// Явный запуск ROOT: ФУМ_ПРОФИЛЬ_LLM=1; по умолчанию профиль отключён.
/// Все HTTP-ответы синтетические; URLSession и реальные поставщики не вызываются.
@Suite("Малый монотонный профиль LLM", .serialized)
struct ПрофильLLM {
  @Test(
    "300 UTF-8 кадров SSE и 1000 повторов сохранённого вызова",
    .enabled(if: ProcessInfo.processInfo.environment["ФУМ_ПРОФИЛЬ_LLM"] == "1")
  )
  func измеритьРазборИПовтор() async throws {
    try измеритьSSEПрофиляLLM()
    for повтор in 1...3 { try await измеритьКэшПрофиляLLM(повтор: повтор) }
  }
}

private struct КорпусSSEПрофиляLLM {
  let поток: Data
  let данныеКадров: [Data]
  let ожидаемыеДанные: Data

  init() {
    var поток = Data()
    var данныеКадров: [Data] = []
    var ожидаемыеДанные = Data()
    for номер in 0..<300 {
      // Есть кириллица, четырёхбайтовый символ и разложенная Unicode-последовательность.
      let данные = Data("{\"номер\":\(номер),\"текст\":\"Ёж 🧠 café e\u{301}\"}".utf8)
      поток.append(Data("id: \(номер)\r\nevent: профиль-ёж\r\ndata: ".utf8))
      поток.append(данные)
      поток.append(Data("\r\n\r\n".utf8))
      данныеКадров.append(данные)
      ожидаемыеДанные.append(данные)
    }
    self.поток = поток
    self.данныеКадров = данныеКадров
    self.ожидаемыеДанные = ожидаемыеДанные
  }
}

private struct ИзмерениеSSEПрофиляLLM: Encodable, Sendable {
  let схема = "fum.профиль-sse-llm.1"
  let часы = "ContinuousClock"
  let единицаВремени = "нс"
  let граница = "создание разбора, подача фрагментов, завершение и сборка кадров"
  let исключено = "подготовка корпуса и фрагментов, хэширование, проверки и печать"
  let повтор: Int
  let размерФрагмента: Int
  let числоФрагментов: Int
  let байтовВхода: Int
  let входSHA256: String
  let числоКадров: Int
  let сырыеРамкиSHA256: String
  let данныеКадровSHA256: String
  let длительностьНс: Int64
  let инвариантыВыполнены: Bool
}

private func измеритьSSEПрофиляLLM() throws {
  let корпус = КорпусSSEПрофиляLLM()
  let входSHA256 = хэшПрофиляLLM(корпус.поток)
  let ожидаемыеДанныеSHA256 = хэшПрофиляLLM(корпус.ожидаемыеДанные)
  let часы = ContinuousClock()

  for повтор in 1...3 {
    for размерФрагмента in [1, 32, 4096] {
      // Нарезка отделена от измеряемого consumer и не использует его вывод.
      var фрагменты: [Data] = []
      var началоФрагмента = 0
      while началоФрагмента < корпус.поток.count {
        let конец = min(началоФрагмента + размерФрагмента, корпус.поток.count)
        фрагменты.append(Data(корпус.поток[началоФрагмента..<конец]))
        началоФрагмента = конец
      }

      let начало = часы.now
      var разбор = РазборSSELLM()
      var кадры: [КадрSSELLM] = []
      for фрагмент in фрагменты {
        кадры.append(contentsOf: try разбор.принять(фрагмент))
      }
      кадры.append(contentsOf: try разбор.завершить())
      let длительность = начало.duration(to: часы.now)

      var сырыеРамки = Data()
      var данныеКадров = Data()
      for кадр in кадры {
        сырыеРамки.append(кадр.сырыеБайты)
        данныеКадров.append(кадр.данные)
      }
      let сырыеРамкиSHA256 = хэшПрофиляLLM(сырыеРамки)
      let данныеКадровSHA256 = хэшПрофиляLLM(данныеКадров)
      let инварианты =
        кадры.count == 300
        && кадры.enumerated().allSatisfy { номер, кадр in
          кадр.идентификатор == String(номер)
            && кадр.событие == "профиль-ёж"
            && кадр.данные == корпус.данныеКадров[номер]
        }
        && сырыеРамки == корпус.поток
        && сырыеРамкиSHA256 == входSHA256
        && данныеКадров == корпус.ожидаемыеДанные
        && данныеКадровSHA256 == ожидаемыеДанныеSHA256
        && разбор.незавершённыйХвост.isEmpty

      try напечататьПрофильLLM(
        ИзмерениеSSEПрофиляLLM(
          повтор: повтор, размерФрагмента: размерФрагмента,
          числоФрагментов: фрагменты.count, байтовВхода: корпус.поток.count,
          входSHA256: входSHA256, числоКадров: кадры.count,
          сырыеРамкиSHA256: сырыеРамкиSHA256,
          данныеКадровSHA256: данныеКадровSHA256,
          длительностьНс: наносекундыПрофиляLLM(длительность),
          инвариантыВыполнены: инварианты
        )
      )
      #expect(инварианты)
    }
  }
}


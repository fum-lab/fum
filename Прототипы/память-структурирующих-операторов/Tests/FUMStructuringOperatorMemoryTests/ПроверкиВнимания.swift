import Foundation
import XCTest

@testable import FUMStructuringOperatorMemory

final class ПроверкиВнимания: XCTestCase {
  private var пакет: URL {
    get throws {
      let текущий = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
      let варианты = [
        текущий,
        текущий.appendingPathComponent("Прототипы/память-структурирующих-операторов"),
      ]
      return try XCTUnwrap(
        варианты.first { кандидат in
          FileManager.default.fileExists(
            atPath: кандидат.appendingPathComponent("Проверки/внимание/случаи.json").path)
        }, "Нужен рабочий каталог FUM либо данного пакета")
    }
  }

  private func прочитать(_ путь: String) throws -> [String: Any] {
    try XCTUnwrap(
      JSONSerialization.jsonObject(with: Data(contentsOf: пакет.appendingPathComponent(путь)))
        as? [String: Any])
  }

  private func данные(_ объект: [String: Any]) throws -> Data {
    try JSONSerialization.data(
      withJSONObject: объект, options: [.sortedKeys, .withoutEscapingSlashes])
  }

  private func определение(_ имя: String) throws -> [String: Any] {
    try прочитать("Sources/FUMStructuringOperatorMemory/Определения/\(имя).json")
  }

  private func вход(_ имя: String) throws -> [String: Any] {
    try прочитать("Проверки/внимание/\(имя).json")
  }

  private func параметры(_ определение: [String: Any], вес: Int = 60, порог: Int = 50) throws
    -> ПараметрыЧувствительности
  {
    let сигналы = try XCTUnwrap(определение["сигналы"] as? [[String: Any]])
    var объект: [String: Any] = [
      "схема": "fum.параметры-чувствительности.1", "версия": 1,
      "веса": Dictionary(
        uniqueKeysWithValues: сигналы.map { ($0["идентификатор"] as! String, вес) }),
      "порог": порог, "хэш": "",
    ]
    объект["хэш"] = sha256Digest(try данные(объект))
    return try ПараметрыЧувствительности.разобрать(данные(объект))
  }

  private func выполнить(
    _ определение: [String: Any], _ вход: [String: Any], вес: Int = 60, порог: Int = 50
  ) throws -> НаблюдениеГрафа {
    try AutomationExecutor.выполнить(
      ОпределениеГрафа.разобрать(данные(определение)),
      вход: СтруктурированныйВход.разобрать(данные(вход)),
      параметры: параметры(определение, вес: вес, порог: порог))
  }

  func testРазныеЦелиОдногоВходаREADME() throws {
    let первое = try определение("актуальность-README")
    var второе = первое
    второе["цель"] = "Документация/README.md"
    let факты = try СтруктурированныйВход.разобрать(данные(вход("README-без-ссылки")))
    let настройки = try параметры(первое)
    // Два прямых вызова одного API на одном входе и одном бинарнике.
    let а = try AutomationExecutor.выполнить(
      ОпределениеГрафа.разобрать(данные(первое)), вход: факты, параметры: настройки)
    let б = try AutomationExecutor.выполнить(
      ОпределениеГрафа.разобрать(данные(второе)), вход: факты, параметры: настройки)
    XCTAssertEqual(а.результат, "расхождение")
    XCTAssertEqual(б.результат, "соответствует")
    XCTAssertNotEqual(а.хэшОпределения, б.хэшОпределения)
    XCTAssertNotEqual(try каноническиеДанные(а.трасса), try каноническиеДанные(б.трасса))
    XCTAssertEqual(а.полномочие, "не предоставлено")
  }

  func testРазныеЦелиОдногоВходаИнтеграции() throws {
    let первое = try определение("потребность-интеграции")
    var второе = первое
    второе["цель"] = "master"
    let факты = try СтруктурированныйВход.разобрать(данные(вход("интеграция-проверенная")))
    let настройки = try параметры(первое)
    let а = try AutomationExecutor.выполнить(
      ОпределениеГрафа.разобрать(данные(первое)), вход: факты, параметры: настройки)
    let б = try AutomationExecutor.выполнить(
      ОпределениеГрафа.разобрать(данные(второе)), вход: факты, параметры: настройки)
    XCTAssertEqual(а.результат, "требуется-интеграция")
    XCTAssertEqual(б.результат, "проверить-включение")
    XCTAssertNotEqual(а.хэшОпределения, б.хэшОпределения)
    XCTAssertNotEqual(try каноническиеДанные(а.трасса), try каноническиеДанные(б.трасса))
  }

  func testЧувствительностьОбоихОпределенийНеМеняетФакты() throws {
    for (имя, пример) in [
      ("актуальность-README", "README-без-ссылки"),
      ("потребность-интеграции", "интеграция-проверенная"),
    ] {
      let граф = try определение(имя)
      let факты = try СтруктурированныйВход.разобрать(данные(вход(пример)))
      let определение = try ОпределениеГрафа.разобрать(данные(граф))
      let а = try AutomationExecutor.выполнить(
        определение, вход: факты, параметры: параметры(граф, вес: 60, порог: 50))
      let б = try AutomationExecutor.выполнить(
        определение, вход: факты, параметры: параметры(граф, вес: 1, порог: 100))
      XCTAssertEqual(а.результат, б.результат)
      XCTAssertEqual(а.хэшОпределения, б.хэшОпределения)
      XCTAssertNotEqual(а.хэшПараметров, б.хэшПараметров)
      XCTAssertNotEqual(а.внимание, б.внимание)
      XCTAssertNotEqual(try каноническиеДанные(а.трасса), try каноническиеДанные(б.трасса))
      XCTAssertNotEqual(try каноническиеДанные(а.вклады), try каноническиеДанные(б.вклады))
      XCTAssertEqual(а.состояние, "активно")
      XCTAssertEqual(б.состояние, "активно")
    }
  }

  func testПовреждениеПроисхожденияДаётUnknownДажеПриНулевыхВесах() throws {
    for (имя, пример, цель) in [
      ("актуальность-README", "README-нарушенная-привязка", "Документация/README.md"),
      ("потребность-интеграции", "интеграция-чужой-OID", "master"),
    ] {
      var граф = try определение(имя)
      let факты = try вход(пример)
      let а = try выполнить(граф, факты, вес: 0, порог: 0)
      граф["цель"] = цель
      let б = try выполнить(граф, факты, вес: 0, порог: 0)
      for исход in [а, б] {
        XCTAssertEqual(исход.результат, "unknown")
        XCTAssertEqual(исход.состояние, "активно")
        XCTAssertFalse(исход.активнаяПричина.isEmpty)
        XCTAssertFalse(исход.неизвестность.isEmpty)
      }
    }
  }

  func testРассмотрениеИПорогНеСнимаютПричину() throws {
    for (имя, пример) in [
      ("актуальность-README", "README-рассмотрено"),
      ("потребность-интеграции", "интеграция-рассмотрено"),
    ] {
      let исход = try выполнить(определение(имя), вход(пример), вес: 0, порог: 10000)
      XCTAssertEqual(исход.состояние, "активно")
      XCTAssertEqual(исход.рассмотрение, "рассмотрено")
      XCTAssertNotEqual(исход.результат, "resolved")
    }
  }

  func testОтрицательныеИКонечныеСценарии() throws {
    let случаи = try прочитать("Проверки/внимание/случаи.json")
    for случай in try XCTUnwrap(случаи["случаи"] as? [[String: String]]) {
      let имя = try XCTUnwrap(случай["вход"])
      let исход = try выполнить(определение(try XCTUnwrap(случай["определение"])), вход(имя))
      XCTAssertEqual(исход.результат, случай["результат"], имя)
      XCTAssertEqual(исход.состояние, случай["состояние"], имя)
    }
  }

  func testПараметрыНеПолучаютМолчаливыхЗначений() throws {
    for объект in [
      [:] as [String: Any], ["схема": "fum.параметры-чувствительности.2"],
      [
        "схема": "fum.параметры-чувствительности.1", "версия": 1, "веса": [:], "порог": -1,
        "хэш": "подмена",
      ],
    ] {
      XCTAssertThrowsError(try ПараметрыЧувствительности.разобрать(данные(объект)))
    }
  }

  func testПоследовательноеУдержаниеУтратыИЧужойОбласти() throws {
    let граф = try определение("потребность-интеграции")
    let утрата = try выполнить(граф, вход("интеграция-revert"))
    XCTAssertEqual(утрата.активныйКритерий, "сохранность-результата")
    var следующий = try вход("интеграция-включена")
    let память = try XCTUnwrap(
      JSONSerialization.jsonObject(with: каноническиеДанные(утрата.память)) as? [String: Any])
    следующий["прежнее"] = память
    let ожидание = try выполнить(граф, следующий)
    XCTAssertEqual(ожидание.результат, "проверить-восстановление")
    XCTAssertEqual(ожидание.активнаяПричина, утрата.активнаяПричина)
    XCTAssertEqual(try каноническиеДанные(ожидание.память), try каноническиеДанные(утрата.память))
    var другаяСтадия = граф
    другаяСтадия["цель"] = "master"
    let чужая = try выполнить(другаяСтадия, следующий)
    XCTAssertEqual(чужая.результат, "unknown")
    XCTAssertEqual(try каноническиеДанные(чужая.память), try каноническиеДанные(утрата.память))
    XCTAssertNotEqual(чужая.область, утрата.область)
  }

  func testПоследовательноеСнятиеПослеТекущейПроверкиREADME() throws {
    let граф = try определение("актуальность-README")
    let расхождение = try выполнить(граф, вход("README-без-ссылки"))
    var исправлено = try вход("README-устранено")
    исправлено["прежнее"] = try JSONSerialization.jsonObject(
      with: каноническиеДанные(расхождение.память))
    let результат = try выполнить(граф, исправлено)
    XCTAssertEqual(результат.результат, "resolved")
    XCTAssertEqual(результат.состояние, "устранено")
    XCTAssertEqual(результат.область, расхождение.область)
    XCTAssertEqual(результат.полномочие, "не предоставлено")
    XCTAssertEqual(
      try каноническиеДанные(результат), try каноническиеДанные(выполнить(граф, исправлено)))
  }

  func testГрафОтклоняетНеизвестныеПоляЦиклыИПовторы() throws {
    var граф = try определение("актуальность-README")
    граф["неизвестное"] = "поле"
    XCTAssertThrowsError(try ОпределениеГрафа.разобрать(данные(граф)))
    граф.removeValue(forKey: "неизвестное")
    граф["узлы"] = [["идентификатор": "цикл", "оператор": "все", "входы": [["узел": "цикл"]]]]
    XCTAssertThrowsError(try ОпределениеГрафа.разобрать(данные(граф)))
    XCTAssertThrowsError(
      try ОпределениеГрафа.разобрать(Data("{\"схема\":\"a\",\"схема\":\"b\"}".utf8)))
  }
}

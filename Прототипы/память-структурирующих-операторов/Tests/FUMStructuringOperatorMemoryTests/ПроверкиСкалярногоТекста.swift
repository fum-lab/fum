import Foundation
import XCTest

@testable import FUMStructuringOperatorMemory

final class ПроверкиСкалярногоТекста: XCTestCase {
  private func определение(_ аргументы: String = "{\"версия\":1}") throws -> ОпределениеОператора {
    let провод = """
      {"схема":"fum.определение-оператора.1","идентификатор":"скалярный-текст","версия":1,
       "правила":[],"шаги":[{"идентификатор":"текст","оператор":"скаляры-в-текст","аргументы":\(аргументы)}]}
      """
    return try ОпределениеОператора.разобрать(Data(провод.utf8))
  }

  private func отказ(
    _ код: String, _ действие: () throws -> Void, файл: StaticString = #filePath,
    строка: UInt = #line
  ) {
    XCTAssertThrowsError(try действие(), file: файл, line: строка) { ошибка in
      XCTAssertEqual((ошибка as? ОшибкаИсполнения)?.код, код, file: файл, line: строка)
    }
  }

  func test_СохраняетСкалярыБезНормализации() throws {
    let скаляры: [UInt32] = [0, 0x451, 0x1F642, 0x65, 0x301, 0xFEFF, 0x10FFFF]
    let ожидание: [UInt8] = [
      0, 0xD1, 0x91, 0xF0, 0x9F, 0x99, 0x82, 0x65, 0xCC, 0x81,
      0xEF, 0xBB, 0xBF, 0xF4, 0x8F, 0xBF, 0xBF,
    ]
    let результат = try AutomationExecutor.выполнить(определение(), вход: .скаляры(скаляры))
    guard case .текст(let текст) = результат.результат else { return XCTFail("Нужен текст") }
    XCTAssertEqual(Array(текст.utf8), ожидание)
    XCTAssertEqual(текст.unicodeScalars.map(\.value), скаляры)
    XCTAssertEqual(результат.выполненоОпераций, 1 + скаляры.count)
    XCTAssertEqual(результат.шаги.count, 1)
    XCTAssertEqual(
      результат.шаги[0].хэшВхода, sha256Digest(ЗначениеОператора.скаляры(скаляры).исходныеБайты))
    XCTAssertEqual(результат.шаги[0].хэшВыхода, sha256Digest(Data(ожидание)))
    let безМеткиПорядкаБайтов = try AutomationExecutor.выполнить(
      определение(), вход: .скаляры([0x451]))
    XCTAssertEqual(безМеткиПорядкаБайтов.результат.исходныеБайты, Data([0xD1, 0x91]))
  }

  func test_ПустотаИГраницыКодировки() throws {
    let пусто = try AutomationExecutor.выполнить(
      определение(), вход: .скаляры([]),
      пределы: ПределыИсполнения(байтовВхода: 0, байтовРезультата: 0, операций: 1, записейТрассы: 0)
    )
    XCTAssertEqual(пусто.результат, .текст(""))
    XCTAssertEqual(пусто.выполненоОпераций, 1)
    let пары: [(UInt32, [UInt8])] = [
      (0x7F, [0x7F]), (0x80, [0xC2, 0x80]), (0x7FF, [0xDF, 0xBF]),
      (0x800, [0xE0, 0xA0, 0x80]), (0xD7FF, [0xED, 0x9F, 0xBF]),
      (0xE000, [0xEE, 0x80, 0x80]), (0xFFFF, [0xEF, 0xBF, 0xBF]),
      (0x10000, [0xF0, 0x90, 0x80, 0x80]), (0x10FFFF, [0xF4, 0x8F, 0xBF, 0xBF]),
    ]
    for (скаляр, байты) in пары {
      let ответ = try AutomationExecutor.выполнить(определение(), вход: .скаляры([скаляр]))
      XCTAssertEqual(ответ.результат.исходныеБайты, Data(байты))
    }
  }

  func test_НеверныеСкалярыИТипВхода() throws {
    let программа = try определение()
    for скаляр: UInt32 in [0xD800, 0xDFFF, 0x110000, UInt32.max] {
      отказ("скаляр") { _ = try AutomationExecutor.выполнить(программа, вход: .скаляры([скаляр])) }
    }
    for вход in [ЗначениеОператора.текст("ё"), .байты([0xD1, 0x91])] {
      отказ("тип-входа") { _ = try AutomationExecutor.выполнить(программа, вход: вход) }
    }
  }

  func test_ЗакрытаяВерсияИПобайтовыйПовтор() throws {
    let исходное = try определение()
    let провод = try исходное.данные()
    let повтор = try ОпределениеОператора.разобрать(провод)
    XCTAssertEqual(повтор, исходное)
    XCTAssertEqual(try повтор.данные(), провод)
    XCTAssertTrue(String(decoding: провод, as: UTF8.self).contains("\"аргументы\":{\"версия\":1}"))
    let а = try AutomationExecutor.выполнить(исходное, вход: .скаляры([0, 0x451, 0x1F642]))
    let б = try AutomationExecutor.выполнить(повтор, вход: .скаляры([0, 0x451, 0x1F642]))
    XCTAssertEqual(try каноническиеДанные(а), try каноническиеДанные(б))
    for аргументы in [
      "{}", "{\"версия\":0}", "{\"версия\":2}", "{\"версия\":\"1\"}",
      "{\"версия\":true}", "{\"версия\":1,\"другое\":0}",
    ] {
      XCTAssertThrowsError(try определение(аргументы))
    }
  }

  func test_ТочныеБюджетыВходаРезультатаИОпераций() throws {
    let программа = try определение()
    let пределы = ПределыИсполнения(
      байтовВхода: 8, байтовРезультата: 3, операций: 3, записейТрассы: 0)
    let ответ = try AutomationExecutor.выполнить(
      программа, вход: .скаляры([65, 0x451]), пределы: пределы)
    XCTAssertEqual(ответ.результат.исходныеБайты, Data([65, 0xD1, 0x91]))
    XCTAssertEqual(ответ.выполненоОпераций, 3)
    отказ("предел-входа") {
      _ = try AutomationExecutor.выполнить(
        программа, вход: .скаляры([65, 0x451]),
        пределы: ПределыИсполнения(байтовВхода: 7))
    }
    отказ("предел-операций") {
      _ = try AutomationExecutor.выполнить(
        программа, вход: .скаляры([65, 0x451]),
        пределы: ПределыИсполнения(операций: 2))
    }
    отказ("предел-результата") {
      _ = try AutomationExecutor.выполнить(
        программа, вход: .скаляры([0x1F642]),
        пределы: ПределыИсполнения(байтовРезультата: 3))
    }
    XCTAssertEqual(
      try AutomationExecutor.выполнить(
        программа, вход: .скаляры([0x1F642]),
        пределы: ПределыИсполнения(байтовРезультата: 4)
      ).результат.исходныеБайты,
      Data([0xF0, 0x9F, 0x99, 0x82]))
    отказ("предел-результата") {
      _ = try AutomationExecutor.выполнить(
        программа, вход: .скаляры([65]),
        пределы: ПределыИсполнения(байтовРезультата: 0))
    }
  }

  func test_ПрежниеБайтовыеПравилаСоединяютсяСТекстом() throws {
    let декодер = try ОпределениеОператора.разобрать(
      РесурсыОпределений.прочитать("UTF-8-в-UTF-32LE"))
    let программа = ОпределениеОператора(
      идентификатор: "UTF8-текст", версия: 1,
      правила: декодер.правила, шаги: [декодер.шаги[0], try определение().шаги[0]])
    let вход = Data([0, 0xD1, 0x91, 0x65, 0xCC, 0x81, 0xF0, 0x9F, 0x99, 0x82])
    let ответ = try AutomationExecutor.выполнить(программа, вход: .байты(Array(вход)))
    XCTAssertEqual(ответ.результат.исходныеБайты, вход)
    XCTAssertEqual(ответ.скаляры, [0, 0x451, 0x65, 0x301, 0x1F642])
    for плохой in [
      [UInt8](arrayLiteral: 0xC0, 0xAF), [0xED, 0xA0, 0x80], [0xF4, 0x90, 0x80, 0x80], [0xD1],
    ] {
      do {
        _ = try AutomationExecutor.выполнить(декодер, вход: .байты(плохой))
        XCTFail("Нужен отказ")
      } catch let исходная as ОшибкаИсполнения {
        XCTAssertThrowsError(try AutomationExecutor.выполнить(программа, вход: .байты(плохой))) {
          ошибка in
          XCTAssertEqual(ошибка as? ОшибкаИсполнения, исходная)
        }
      }
    }
  }

  func test_ПрофильСкалярногоТекста() throws {
    guard let выход = ProcessInfo.processInfo.environment["ФУМ_ВЫХОД_ПРОФИЛЯ_СКАЛЯРОВ"] else {
      throw XCTSkip("Профиль запускается отдельно с приватным выходом")
    }
    let программа = try определение()
    let образец: [UInt32] = [65, 0x451, 0x1F642, 0x65, 0x301, 0, 0xFEFF, 0x10FFFF]
    let скаляры = Array(repeating: образец, count: 4096).flatMap { $0 }
    let вход = ЗначениеОператора.скаляры(скаляры)
    let контроль = try AutomationExecutor.выполнить(программа, вход: вход)
    var ряды: [[String: Any]] = []
    for _ in 0..<7 {
      var замеры: [ЗамерИсполнения] = []
      let ответ = try AutomationExecutor.выполнить(
        программа, вход: вход, профиль: { замеры.append($0) })
      XCTAssertEqual(try каноническиеДанные(ответ), try каноническиеДанные(контроль))
      ряды.append(
        Dictionary(uniqueKeysWithValues: замеры.map { ($0.стадия, $0.наносекунды as Any) }))
    }
    let документ: [String: Any] = [
      "схема": "fum.профиль-скалярного-текста.1", "скаляров": скаляры.count,
      "байтов_входа": вход.исходныеБайты.count,
      "байтов_выхода": контроль.результат.исходныеБайты.count,
      "операций": контроль.выполненоОпераций, "хэш_наблюдения": контроль.хэшНаблюдения,
      "ряды": ряды,
    ]
    try JSONSerialization.data(withJSONObject: документ, options: [.prettyPrinted, .sortedKeys])
      .write(to: URL(fileURLWithPath: выход), options: .withoutOverwriting)
  }
}

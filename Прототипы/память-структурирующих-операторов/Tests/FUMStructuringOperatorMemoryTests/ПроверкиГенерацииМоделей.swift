import Foundation
import XCTest

@testable import FUMStructuringOperatorMemory

final class ПроверкиГенерацииМоделей: XCTestCase {
  private let описание = #"""
    {"схема":"fum.структурный-контракт.1","идентификатор":"fum.пример-ответа","версия":1,
    "происхождение":"Открытая проверочная модель ответа задачи","числа":"целые64-без-дробей",
    "вход":"Ответ","выход":"Срез",
    "модели":[
      {"имя":"Ответ","идентификатор":"fum.пример-ответа.вход.1","поля":[
        {"имя":"текст","ключ":"text","тип":"строка","присутствие":"обязательно","null":"нет","варианты":[]}]},
      {"имя":"Срез","идентификатор":"fum.пример-ответа.выход.1","поля":[
        {"имя":"ответ","ключ":"ответ","тип":"строка","присутствие":"обязательно","null":"нет","варианты":[]}]}],
    "переменные":[],"результат":{"ответ":["путь",["переменная","вход"],"text"]}}
    """#

  private func программа(_ язык: String) throws -> ОпределениеОператора {
    let текст = """
      {"схема":"fum.определение-оператора.1","идентификатор":"fum.генерация.\(язык)","версия":1,
      "правила":[],"шаги":[
      {"идентификатор":"описание","оператор":"разобрать-структурный-контракт","аргументы":{}},
      {"идентификатор":"представление","оператор":"породить-представление","аргументы":{"язык":"\(язык)","профиль":"fum.модели-и-проекция.1"}}]}
      """
    return try ОпределениеОператора.разобрать(Data(текст.utf8))
  }

  func test_ОбщийИсполнительПорождаетОбаПредставленияИСледы() throws {
    for язык in ["Swift", "Python"] {
      let определение = try программа(язык)
      let первый = try AutomationExecutor.выполнить(определение, вход: .текст(описание))
      let второй = try AutomationExecutor.выполнить(определение, вход: .текст(описание))
      XCTAssertEqual(первый, второй)
      XCTAssertEqual(первый.шаги.map(\.идентификатор), ["описание", "представление"])
      guard case .текст(let текст) = первый.результат else { return XCTFail("Нужен исходный текст") }
      XCTAssertTrue(текст.contains("Ответ"))
      XCTAssertTrue(текст.contains(язык == "Swift" ? "Codable" : "dataclass"))
      XCTAssertTrue(текст.contains("fum.модели-и-проекция.1"))
      let изменённый = описание.replacingOccurrences(of: "\"ответ\"", with: "\"выбранное\"")
      XCTAssertNotEqual(первый.результат,
        try AutomationExecutor.выполнить(определение, вход: .текст(изменённый)).результат)
    }
  }

  func test_НеоднозначноеОписаниеИНеизвестнаяОперацияОтклоняются() throws {
    let определение = try программа("Swift")
    for вход in [описание.replacingOccurrences(of: "\"строка\"", with: "\"неизвестный\""),
      описание.replacingOccurrences(of: "\"путь\"", with: "\"исполнить-строку\""),
      описание.replacingOccurrences(of: "\"версия\":1", with: "\"версия\":1,\"версия\":2"),
      описание.replacingOccurrences(of: "\"text\"]", with: "\"text\",null]")]
    {
      XCTAssertThrowsError(try AutomationExecutor.выполнить(определение, вход: .текст(вход)))
    }
    XCTAssertThrowsError(try программа("Ruby"))
  }
  func test_СлужебныеИменаИНевернаяФормаОтклоняютсяДоВывода() throws {
    let определение = try программа("Python")
    for имя in ["описание_моделей", "КонтрактМоделей", "Поле", "Ключи", "строка", "спроецировать"] {
      let вход = описание.replacingOccurrences(of: "Ответ", with: имя)
      XCTAssertThrowsError(try AutomationExecutor.выполнить(определение, вход: .текст(вход)), имя)
    }
    for вход in [
      описание.replacingOccurrences(of: "\"результат\":{\"ответ\":", with: "\"результат\":{\"неизвестное\":"),
      описание.replacingOccurrences(of: "[\"путь\",[\"переменная\",\"вход\"],\"text\"]", with: "[\"первый\",\"абв\"]")
    ] { XCTAssertThrowsError(try AutomationExecutor.выполнить(определение, вход: .текст(вход))) }
  }

}

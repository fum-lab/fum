import XCTest
@testable import FUMStructuringOperatorMemory

final class ПроверкиЧтенияБайтов: XCTestCase {
  func test_ЧитаетБеззнаковыеЧислаВОбоихПорядках() throws {
    let читатель = ЧитательБайтов([0x12, 0x34, 0x56, 0x78])

    XCTAssertEqual(
      try читатель.прочитатьБеззнаковое(соСмещения: 0, длиной: 4, порядок: .старшийПервым),
      ПрочитанноеБеззнаковоеЧисло(значение: 0x12345678, диапазонИсходныхБайтов: 0..<4)
    )
    XCTAssertEqual(
      try читатель.прочитатьБеззнаковое(соСмещения: 0, длиной: 4, порядок: .младшийПервым),
      ПрочитанноеБеззнаковоеЧисло(значение: 0x78563412, диапазонИсходныхБайтов: 0..<4)
    )
  }

  func test_ПоддерживаетПолнуюШиринуUInt64() throws {
    let результат = try ЧитательБайтов(Array(repeating: 0xff, count: 8))
      .прочитатьБеззнаковое(соСмещения: 0, длиной: 8, порядок: .старшийПервым)

    XCTAssertEqual(результат.значение, UInt64.max)
    XCTAssertEqual(результат.диапазонИсходныхБайтов, 0..<8)
  }

  func test_ОтклоняетНедопустимуюШирину() {
    let читатель = ЧитательБайтов([0])

    XCTAssertThrowsError(try читатель.прочитатьБеззнаковое(соСмещения: 0, длиной: 0, порядок: .старшийПервым)) {
      XCTAssertEqual($0 as? ОшибкаЧтенияБайтов, .недопустимаяДлина(числоБайтов: 0))
    }
    XCTAssertThrowsError(try читатель.прочитатьБеззнаковое(соСмещения: 0, длиной: 9, порядок: .старшийПервым)) {
      XCTAssertEqual($0 as? ОшибкаЧтенияБайтов, .недопустимаяДлина(числоБайтов: 9))
    }
  }

  func test_ОтклоняетОтрицательноеСмещение() {
    XCTAssertThrowsError(
      try ЧитательБайтов([0]).прочитатьБеззнаковое(соСмещения: -1, длиной: 1, порядок: .старшийПервым)
    ) {
      XCTAssertEqual($0 as? ОшибкаЧтенияБайтов, .отрицательноеСмещение(смещение: -1))
    }
  }

  func test_ОтклоняетПереполнениеКонечногоСмещения() {
    XCTAssertThrowsError(
      try ЧитательБайтов([0]).прочитатьБеззнаковое(соСмещения: Int.max, длиной: 1, порядок: .старшийПервым)
    ) {
      XCTAssertEqual(
        $0 as? ОшибкаЧтенияБайтов,
        .переполнениеКонечногоСмещения(смещение: Int.max, числоБайтов: 1)
      )
    }
  }

  func test_ОтклоняетДиапазонВнеВхода() {
    XCTAssertThrowsError(
      try ЧитательБайтов([0, 1]).прочитатьБеззнаковое(соСмещения: 1, длиной: 2, порядок: .старшийПервым)
    ) {
      XCTAssertEqual($0 as? ОшибкаЧтенияБайтов, .внеВхода(смещение: 1, числоБайтов: 2, размерВхода: 2))
    }
  }

  func test_РазрешаетЧтениеПоследнегоБайтаПустогоДиапазонаОтклоняяНулевуюШирину() throws {
    let результат = try ЧитательБайтов([0xab])
      .прочитатьБеззнаковое(соСмещения: 0, длиной: 1, порядок: .старшийПервым)

    XCTAssertEqual(результат.значение, 0xab)
    XCTAssertEqual(результат.диапазонИсходныхБайтов, 0..<1)
  }
}

import Foundation
import XCTest

@testable import FUMStructuringOperatorMemory

final class ПроверкиГрафаJSON: XCTestCase {
  private func программа(_ выражение: String, переменные: String = "[]") throws -> ОпределениеОператора {
    let текст = """
      {"схема":"fum.определение-оператора.1","идентификатор":"fuma.расчёт","версия":1,
      "правила":[],"шаги":[{"идентификатор":"расчёт","оператор":"вычислить-JSON",
      "аргументы":{"граф":{"схема":"fuma.граф-JSON.1","числа":"целые64-без-дробей",
      "переменные":\(переменные),"результат":\(выражение)}}}]}
      """
    return try ОпределениеОператора.разобрать(Data(текст.utf8))
  }

  private func выполнить(_ выражение: String, вход: String = "{}",
                         пределы: ПределыИсполнения = .init()) throws -> НаблюдениеОператора {
    try AutomationExecutor.выполнить(программа(выражение), вход: .текст(вход), пределы: пределы)
  }

  func test_ПодпискаВЦентахИПовторБезСкрытогоСостояния() throws {
    let выражение = #"{"год_USD_центы":["умножить",["путь",["переменная","вход"],"месяц"],12]}"#
    let первый = try выполнить(выражение, вход: #"{"месяц":20000}"#)
    XCTAssertEqual(первый.результат, .текст(#"{"год_USD_центы":240000}"#))
    XCTAssertEqual(первый, try выполнить(выражение, вход: #"{"месяц":20000}"#))
    XCTAssertEqual(первый.шаги.map(\.идентификатор), ["расчёт"])
  }

  func test_НеизвестноеНеПревращаетсяВНулевуюЦену() throws {
    let переменные = #"""
      [{"имя":"суммы","значение":["отобразить",["путь",["переменная","вход"],"строки"],"строка",
        ["если",["равно",["путь",["переменная","строка"],"количество"],0],0,
          ["умножить",["путь",["переменная","строка"],"количество"],
            ["путь",["переменная","строка"],"цена"]]]]},
       {"имя":"неизвестно","значение":["сумма",["отобразить",["переменная","суммы"],"сумма",
          ["если",["равно",["переменная","сумма"],["null"]],1,0]]]}]
      """#
    let результат = #"""
      {"известно":["сумма",["отобразить",["переменная","суммы"],"сумма",
        ["если",["равно",["переменная","сумма"],["null"]],0,["переменная","сумма"]]]],
       "неизвестно":["переменная","неизвестно"],"всего":["сумма",["переменная","суммы"]]}
      """#
    let определение = try программа(результат, переменные: переменные)
    let вход = #"{"строки":[{"количество":2,"цена":600},{"количество":1,"цена":null},{"количество":1,"цена":800},{"количество":0,"цена":null}]}"#
    let наблюдение = try AutomationExecutor.выполнить(определение, вход: .текст(вход))
    XCTAssertEqual(наблюдение.результат, .текст(#"{"всего":null,"известно":2000,"неизвестно":1}"#))
  }

  func test_ЛениваяВетвьИСтрогиеТипы() throws {
    XCTAssertEqual(try выполнить(#"["если",["истина"],17,["умножить",9223372036854775807,2]]"#).результат, .текст("17"))
    for вход in [#"{"цена":true}"#, #"{"цена":1.5}"#, #"{"цена":1e2}"#, #"{}"#] {
      XCTAssertThrowsError(try выполнить(#"["умножить",["путь",["переменная","вход"],"цена"],2]"#, вход: вход))
    }
    XCTAssertThrowsError(try выполнить(#"["умножить",9223372036854775807,2]"#))
    XCTAssertThrowsError(try выполнить(#"["сумма",["массив",9223372036854775807,1]]"#))
  }

  func test_ГрафНеДопускаетЦиклыИНеизвестныеПримитивы() throws {
    XCTAssertThrowsError(try программа(#"["переменная","а"]"#, переменные: #"[{"имя":"а","значение":["переменная","а"]}]"#))
    XCTAssertThrowsError(try программа(#"["запустить-shell","echo unsafe"]"#))
    XCTAssertThrowsError(try программа(#"["умножить",1]"#))
  }

  func test_ПовторыКлючейИПобайтовыеСтроки() throws {
    for вход in [#"{"а":1,"\u0430":2}"#, "{\"ё\":1,\"е\u{0308}\":2}"] {
      XCTAssertThrowsError(try выполнить(#"["переменная","вход"]"#, вход: вход))
    }
    XCTAssertEqual(try выполнить("[\"равно\",\"ё\",\"е\u{0308}\"]").результат, .текст("false"))
    XCTAssertThrowsError(try выполнить("[\"путь\",[\"переменная\",\"вход\"],\"е\u{0308}\"]", вход: "{\"ё\":1}"))
  }

  func test_БюджетыОстанавливаютРазмножениеИОбход() throws {
    XCTAssertThrowsError(try выполнить(#"["переменная","вход"]"#, пределы: .init(операций: 1)))
    let выражение = #"["отобразить",["массив",1,2,3],"номер",["переменная","вход"]]"#
    XCTAssertThrowsError(try выполнить(выражение, вход: #"{"текст":"длинная строка"}"#, пределы: .init(байтовРезультата: 70)))
    XCTAssertThrowsError(try выполнить(#"["переменная","вход"]"#, вход: String(repeating: "[", count: 17)+"0"+String(repeating: "]", count: 17)))
  }

  func test_ПроекцияСодержимогоИПодписиИсполняютсяГрафом() throws {
    let выражение = #"{"слайды":["отобразить",["путь",["переменная","вход"],"заголовки"],"заголовок",{"заголовок":["переменная","заголовок"],"подпись":["соединить","Горизонт: ",["в-строку",12]," месяцев"]}]}"#
    XCTAssertEqual(try выполнить(выражение, вход: #"{"заголовки":["FUMA"]}"#).результат,
      .текст(#"{"слайды":[{"заголовок":"FUMA","подпись":"Горизонт: 12 месяцев"}]}"#))
  }

  func test_ОбщиеСлайдыПрисоединяютсяБезПодменыПорядка() throws {
    XCTAssertEqual(try выполнить(#"["соединить-массивы",["массив",1,2],["массив"],["массив",3]]"#).результат, .текст("[1,2,3]"))
    XCTAssertThrowsError(try выполнить(#"["соединить-массивы",["массив",1],7]"#))
  }

  func test_БольшиеПовторныеСравненияСписываютБюджет() throws {
    let вход = try String(decoding: JSONSerialization.data(withJSONObject: ["текст": String(repeating: "я", count: 500), "строки": Array(repeating: 0, count: 20)]), as: UTF8.self)
    let выражение = #"["отобразить",["путь",["переменная","вход"],"строки"],"строка",["равно",["путь",["переменная","вход"],"текст"],["путь",["переменная","вход"],"текст"]]]"#
    XCTAssertThrowsError(try выполнить(выражение, вход: вход, пределы: .init(операций: 10000))) { ошибка in
      XCTAssertEqual((ошибка as? ОшибкаИсполнения)?.код, "предел-операций")
    }
  }

  func test_ПустойПромежуточныйОбъектИГлубокийВыходОграничены() throws {
    let определение = try программа("0", переменные: #"[{"имя":"пустой","значение":{}}]"#)
    XCTAssertThrowsError(try AutomationExecutor.выполнить(определение, вход: .текст("0"), пределы: .init(байтовРезультата: 1)))
    let переменные = (0..<18).map { номер in
      "{\"имя\":\"узел\(номер)\",\"значение\":[\"массив\",[\"переменная\",\"\(номер == 0 ? "вход" : "узел\(номер-1)")\"]]}"
    }.joined(separator: ",")
    let глубокое = try программа(#"["переменная","узел17"]"#, переменные: "["+переменные+"]")
    XCTAssertThrowsError(try AutomationExecutor.выполнить(глубокое, вход: .текст("0")))
  }

  func test_ДиапазонДенегИТочноеДелениеБезСкрытогоОкругления() throws {
    XCTAssertEqual(try выполнить(#"["потребовать-диапазон",20000,0,9223372036854775807]"#).результат, .текст("20000"))
    XCTAssertThrowsError(try выполнить(#"["потребовать-диапазон",-1,0,100]"#))
    XCTAssertThrowsError(try выполнить(#"["потребовать-диапазон",101,0,100]"#))
    XCTAssertEqual(try выполнить(#"["разделить-точно",190000000,100]"#).результат, .текст("1900000"))
    for выражение in [#"["разделить-точно",1,0]"#, #"["разделить-точно",1,3]"#, #"["разделить-точно",-9223372036854775808,-1]"#] {
      XCTAssertThrowsError(try выполнить(выражение))
    }
    XCTAssertEqual(try выполнить(#"["разделить-точно",["null"],100]"#).результат, .текст("null"))
  }

  func test_ЯвноеОкруглениеВремениВнизНеПрименяетсяКДеньгам() throws {
    XCTAssertEqual(try выполнить(#"["разделить-неотрицательные-вниз",1440000,385]"#).результат, .текст("3740"))
    XCTAssertThrowsError(try выполнить(#"["разделить-неотрицательные-вниз",1,0]"#))
    XCTAssertThrowsError(try выполнить(#"["разделить-неотрицательные-вниз",-1,3]"#))
    XCTAssertThrowsError(try выполнить(#"["разделить-точно",1,3]"#))
  }
}

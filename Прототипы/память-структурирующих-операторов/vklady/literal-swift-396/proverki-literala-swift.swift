import Foundation
import Testing
@testable import FUMStructuringOperatorMemory

struct ПроверкиЛитералаSwift {
  private func граф(_ выражение: УзелОпределения) throws -> ГрафJSON {
    let описание = УзелОпределения.объект([
      "схема": .строка("fuma.граф-JSON.1"),
      "числа": .строка("целые64-без-дробей"),
      "переменные": .массив([]), "результат": выражение
    ])
    var разбор = try РазборОпределения(каноническиеДанные(описание))
    return try ГрафJSON(разбор.разобрать())
  }

  private func выражение(
    _ значение: УзелОпределения, _ предел: УзелОпределения = .целое(65_536)
  ) -> УзелОпределения {
    .массив([.строка("литерал-Swift"), значение, предел])
  }

  private func отказ(_ код: String, _ действие: () throws -> Void) {
    do {
      try действие()
      Issue.record("Ожидался отказ: \(код)")
    } catch let ошибка as ОшибкаИсполнения {
      #expect(ошибка.код == код)
    } catch {
      Issue.record("Неожиданный тип отказа: \(error)")
    }
  }

  private func построить(_ строка: String, _ исходник: Int = 65_536, _ json: Int = 262_144) throws -> String {
    try ЛитералSwift.построить(
      строка, пределИсходника: исходник, пределJSON: json, операция: {})
  }

  @Test("новый оператор исполняется настоящим графом")
  func исполняетсяГрафом() throws {
    let программа = try граф(выражение(.строка("a"), .целое(8)))
    let результат = try программа.вычислитьУзел(.пусто, пределБайтов: 13, операция: {})
    #expect(результат == .строка(#""\u{61}""#))
  }

  @Test("закреплённые литералы и пустая строка")
  func точноеПредставление() throws {
    let случаи = [
      ("", #""""#), ("a", #""\u{61}""#),
      ("\"\\\n", #""\u{22}\u{5c}\u{a}""#),
      ("ё", #""\u{451}""#), ("е\u{0308}", #""\u{435}\u{308}""#),
      ("🧭", #""\u{1f9ed}""#), ("\u{0}", #""\u{0}""#)
    ]
    for (вход, ожидается) in случаи {
      #expect(try Data(построить(вход).utf8) == Data(ожидается.utf8))
    }
  }

  @Test("раздельные точные границы Swift и JSON")
  func точныеПределы() throws {
    for вход in ["", "a", "\"\\\n", "е\u{0308}", "🧭", "\u{0}\u{2028}"] {
      let результат = try построить(вход)
      let исходник = результат.utf8.count
      let json = try каноническиеДанные(результат).count
      let оценка = try ЛитералSwift.оценить(
        вход, пределИсходника: исходник, пределJSON: json, операция: {})
      #expect(оценка == .init(исходник: исходник, json: json))
      #expect(try построить(вход, исходник, json) == результат)
      отказ("предел-литерала") { _ = try построить(вход, исходник - 1, json) }
      отказ("предел-результата") { _ = try построить(вход, исходник, json - 1) }
    }
  }

  @Test("общий бюджет проходит через граф, а не локальную константу")
  func графПроверяетОбаПредела() throws {
    let программа = try граф(выражение(.строка("a"), .целое(8)))
    _ = try программа.вычислитьУзел(.пусто, пределБайтов: 13, операция: {})
    отказ("предел-результата") {
      _ = try программа.вычислитьУзел(.пусто, пределБайтов: 12, операция: {})
    }
    отказ("предел-литерала") {
      _ = try граф(выражение(.строка("a"), .целое(7)))
        .вычислитьУзел(.пусто, пределБайтов: 13, операция: {})
    }
  }

  @Test("неверные типы не приводятся к строке или целому")
  func типыОтклоняются() throws {
    for вход: УзелОпределения in [.целое(7), .логическое(true), .пусто, .массив([]), .объект([:])] {
      отказ("тип-JSON") {
        _ = try граф(выражение(.массив([.строка("переменная"), .строка("вход")])))
          .вычислитьУзел(вход, пределБайтов: 262_144, операция: {})
      }
    }
    for предел: УзелОпределения in [.строка("8"), .массив([.строка("истина")]), .массив([.строка("null")])] {
      отказ("тип-JSON") {
        _ = try граф(выражение(.строка("a"), предел))
          .вычислитьУзел(.пусто, пределБайтов: 262_144, операция: {})
      }
    }
  }

  @Test("арность и неизвестный оператор проверяются до исполнения")
  func арность() {
    for части: [УзелОпределения] in [
      [.строка("литерал-Swift")], [.строка("литерал-Swift"), .строка("a")],
      [.строка("литерал-Swift"), .строка("a"), .целое(8), .целое(9)],
      [.строка("неизвестный-литерал"), .строка("a"), .целое(8)]
    ] {
      отказ("граф") { _ = try граф(.массив(части)) }
    }
  }

  @Test("отрицательный бюджет явно отклоняется")
  func отрицательныеПределы() {
    отказ("диапазон-JSON") { _ = try построить("", -1, 6) }
    отказ("диапазон-JSON") { _ = try построить("", 2, -1) }
    отказ("диапазон-JSON") {
      _ = try граф(выражение(.строка(""), .целое(-1)))
        .вычислитьУзел(.пусто, пределБайтов: 128, операция: {})
    }
  }

  @Test("checked addition не допускает переполнение")
  func переполнение() throws {
    #expect(try ЛитералSwift.сложитьРазмеры(Int.max - 1, 1) == Int.max)
    #expect(try ЛитералSwift.сложитьРазмеры(0, 0) == 0)
    отказ("переполнение-JSON") { _ = try ЛитералSwift.сложитьРазмеры(Int.max, 1) }
  }

  @Test("остановка сохраняется в расчёте, перед буфером и при записи")
  func остановка() throws {
    let сигнал = ОшибкаИсполнения("тест-остановки", "Остановить")
    for номер in [1, 4, 5, 7] {
      var вызовов = 0
      do {
        _ = try ЛитералSwift.построить("abc", пределИсходника: 100, пределJSON: 100) {
          вызовов += 1
          if вызовов == номер { throw сигнал }
        }
        Issue.record("Остановка не передана")
      } catch let ошибка as ОшибкаИсполнения {
        #expect(ошибка == сигнал)
        #expect(вызовов == номер)
      }
    }
  }

  @Test("невозможный пустой результат отклоняется без обхода входа")
  func раннийОтказ() {
    var вызовов = 0
    отказ("предел-литерала") {
      _ = try ЛитералSwift.построить("abc", пределИсходника: 1, пределJSON: 100) { вызовов += 1 }
    }
    #expect(вызовов == 0)
    отказ("предел-результата") {
      _ = try ЛитералSwift.построить("abc", пределИсходника: 100, пределJSON: 5) { вызовов += 1 }
    }
    #expect(вызовов == 0)
  }

  @Test("динамический map сохраняет порядок литералов")
  func отображение() throws {
    let программа = try граф(.массив([
      .строка("отобразить"), .массив([.строка("переменная"), .строка("вход")]),
      .строка("элемент"), выражение(.массив([.строка("переменная"), .строка("элемент")]))
    ]))
    let результат = try программа.вычислитьУзел(
      .массив([.строка("a"), .строка(""), .строка("b")]), пределБайтов: 262_144, операция: {})
    #expect(результат == .массив([.строка(#""\u{61}""#), .строка(#""""#), .строка(#""\u{62}""#)]))
  }

  @Test("ленивая ветвь не исполняет ошибочный литерал")
  func ленивоеУсловие() throws {
    let программа = try граф(.массив([
      .строка("если"), .массив([.строка("истина")]), .строка("готово"), выражение(.целое(7))
    ]))
    #expect(try программа.вычислитьУзел(.пусто, пределБайтов: 262_144, операция: {}) == .строка("готово"))
  }

  @Test("JSON-транспорт возвращает литерал без изменения байтов")
  func текстовыйВход() throws {
    let программа = try граф(выражение(.массив([.строка("переменная"), .строка("вход")])))
    let вход = "е\u{0308}\n\\(1 + 1)"
    let json = try программа.вычислить(
      String(decoding: каноническиеДанные(вход), as: UTF8.self), пределБайтов: 262_144, операция: {})
    let результат = try JSONDecoder().decode(String.self, from: Data(json.utf8))
    #expect(Data(результат.utf8) == Data(try построить(вход).utf8))
  }
}

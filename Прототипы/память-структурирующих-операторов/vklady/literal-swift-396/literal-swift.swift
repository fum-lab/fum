import Foundation

/// Чистое кодирование строки в обычный Swift-литерал без интерполяции.
/// Все скаляры экранируются: исходные UTF-8-байты не нормализуются.
enum ЛитералSwift {
  struct Размер: Equatable {
    let исходник: Int
    let json: Int
  }

  static func сложитьРазмеры(_ левое: Int, _ правое: Int) throws -> Int {
    let (сумма, переполнение) = левое.addingReportingOverflow(правое)
    guard !переполнение else {
      throw ОшибкаИсполнения("переполнение-JSON", "Переполнение размера Swift-литерала")
    }
    return сумма
  }

  private static func цифр(_ значение: UInt32) -> Int {
    var остаток = значение
    var количество = 1
    while остаток >= 16 {
      остаток >>= 4
      количество += 1
    }
    return количество
  }

  static func оценить(
    _ строка: String, пределИсходника: Int, пределJSON: Int,
    операция: () throws -> Void
  ) throws -> Размер {
    guard пределИсходника >= 0, пределJSON >= 0 else {
      throw ОшибкаИсполнения("диапазон-JSON", "Пределы Swift-литерала неотрицательны")
    }
    // Две кавычки исходника; JSON дополнительно экранирует их и обрамляет строку.
    var исходник = 2
    var json = 6
    func проверитьПределы() throws {
      guard исходник <= пределИсходника else {
        throw ОшибкаИсполнения("предел-литерала", "Превышен бюджет Swift-исходника")
      }
      guard json <= пределJSON else {
        throw ОшибкаИсполнения("предел-результата", "Swift-литерал превышает общий JSON-бюджет")
      }
    }
    try проверитьПределы()
    for скаляр in строка.unicodeScalars {
      try операция()
      let ширина = цифр(скаляр.value)
      исходник = try сложитьРазмеры(исходник, 4 + ширина)
      // В JSON обратная косая каждой последовательности экранируется ещё раз.
      json = try сложитьРазмеры(json, 5 + ширина)
      try проверитьПределы()
    }
    return Размер(исходник: исходник, json: json)
  }

  static func построить(
    _ строка: String, пределИсходника: Int, пределJSON: Int,
    операция: () throws -> Void
  ) throws -> String {
    let размер = try оценить(
      строка, пределИсходника: пределИсходника, пределJSON: пределJSON,
      операция: операция)
    // Вызывающий код может остановить работу до выделения результирующего буфера.
    try операция()
    var результат = String()
    результат.reserveCapacity(размер.исходник)
    результат.append("\"")
    for скаляр in строка.unicodeScalars {
      try операция()
      результат.append("\\u{")
      результат.append(String(скаляр.value, radix: 16))
      результат.append("}")
    }
    результат.append("\"")
    return результат
  }
}

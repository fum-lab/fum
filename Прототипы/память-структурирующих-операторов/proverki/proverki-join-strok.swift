import Foundation
import Testing
@testable import FUMStructuringOperatorMemory

struct ПроверкиСоединенияСтрок {
  private func выполнить(
    _ выражение: String, вход: String = "{}", пределы: ПределыИсполнения = .init()
  ) throws -> НаблюдениеОператора {
    let определение = """
      {"схема":"fum.определение-оператора.1","идентификатор":"проверка-join","версия":1,
      "правила":[],"шаги":[{"идентификатор":"результат","оператор":"вычислить-JSON",
      "аргументы":{"граф":{"схема":"fuma.граф-JSON.1","числа":"целые64-без-дробей",
      "переменные":[],"результат":\(выражение)}}}]}
      """
    return try AutomationExecutor.выполнить(
      ОпределениеОператора.разобрать(Data(определение.utf8)),
      вход: .текст(вход), пределы: пределы)
  }

  @Test("динамический map чисел соединяется точными LF байтами")
  func динамическийMapДаётСтрокуСПорядком() throws {
    let выражение = #"["соединить-строки",["отобразить",["массив",3,-2,0],"число",["в-строку",["переменная","число"]]],"\n"]"#
    let наблюдение = try выполнить(выражение)

    #expect(наблюдение.результат == .текст(#""3\n-2\n0""#))
  }

  @Test("пустой массив, один элемент, порядок и UTF-8 разделителя сохраняются")
  func границыИUnicodeРазделителя() throws {
    let случаи: [(String, String)] = [
      (#"["соединить-строки",["массив"],"/"]"#, ""),
      (#"["соединить-строки",["массив","единственный"],"!"]"#, "единственный"),
      (#"["соединить-строки",["массив","a","b","c"],"::"]"#, "a::b::c"),
      (#"["соединить-строки",["массив","я","ё"],"🧭"]"#, "я🧭ё"),
      (#"["соединить-строки",["массив","ё","е\u0308"],"/"]"#, "ё/е\u{0308}"),
    ]

    for (выражение, ожидаемыйJSON) in случаи {
      let результат = try выполнить(выражение).результат
      if case .текст(let json) = результат {
        let декодированный = try JSONDecoder().decode(String.self, from: Data(json.utf8))
        #expect(декодированный == ожидаемыйJSON)
        #expect(Data(декодированный.utf8) == Data(ожидаемыйJSON.utf8))
      } else {
        Issue.record("Ожидался JSON-текст результата JOIN")
      }
    }
  }

  @Test("элемент неверного типа даёт типизированный отказ")
  func неверныйТипОтклоняется() throws {
    for выражение in [
      #"["соединить-строки",["массив","ok",7],","]"#,
      #"["соединить-строки",7,","]"#,
      #"["соединить-строки",["массив","ok"],7]"#,
    ] {
      do {
        _ = try выполнить(выражение)
        Issue.record("Ожидался типизированный отказ для неверного типа")
      } catch let ошибка as ОшибкаИсполнения {
        #expect(ошибка.код == "тип-JSON")
      }
    }
  }

  @Test("соединение использует общий точный предел JSON результата")
  func точныйПределИПревышениеНаБайт() throws {
    let выражение = #"["соединить-строки",["массив","a","b"],"||||||||||"]"#
    let точное = try выполнить(выражение, пределы: .init(байтовРезультата: 14))
    #expect(точное.результат == .текст(#""a||||||||||b""#))

    do {
      _ = try выполнить(выражение, пределы: .init(байтовРезультата: 13))
      Issue.record("Ожидалось превышение общего бюджета на один байт")
    } catch let ошибка as ОшибкаИсполнения {
      #expect(ошибка.код == "предел-результата")
    }
  }

  @Test("арифметика размера JOIN явно отклоняет переполнение")
  func переполнениеРазмеровТипизированоОтклоняется() throws {
    do {
      _ = try РазмерСоединенияСтрок.прибавитьПроверенно(Int.max, 1)
      Issue.record("Ожидалось переполнение сложения размера")
    } catch let ошибка as ОшибкаИсполнения {
      #expect(ошибка.код == "переполнение-JSON")
    }
  }

  @Test("оценка бюджета совпадает с фактической JSON-кодировкой управляющих и Unicode символов")
  func размерОценкиСовпадаетСКодировкойJSON() throws {
    let значение = "кавычка: \"; косая: \\; строки: \n\t\u{0001}; Unicode: 🧭/ "
    let оценка = try РазмерСоединенияСтрок.проверить(
      [значение], разделитель: "не используется", пределJSON: Int.max, операция: {})
    #expect(оценка.размерJSON == (try каноническиеДанные(значение)).count)
  }
}

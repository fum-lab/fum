import AppKit
import Foundation
import SwiftUI
import ДеревоДокументовЯдро

private enum ИтогСканирования: Sendable {
  case готово(СнимокДерева)
  case ошибка(String)
}

@MainActor
final class МодельПриложения: ObservableObject {
  let корень: URL
  let графическиеРесурсы: ГрафическиеРесурсы?

  @Published private(set) var снимок: СнимокДерева?
  @Published private(set) var раскладка: РезультатРаскладки?
  @Published private(set) var сообщениеОбОшибке: String?
  @Published var запросПоиска = ""
  @Published private(set) var выбранныйИдентификатор: String?
  @Published private(set) var свёрнутыеИдентификаторы: Set<String> = []
  @Published private(set) var поколениеВписывания = 0
  @Published private(set) var идётСканирование = false
  private var задачаСканирования: Task<Void, Never>?

  init(корень: URL, графическиеРесурсы: ГрафическиеРесурсы?) {
    self.корень = корень
    self.графическиеРесурсы = графическиеРесурсы
    обновить()
  }

  var выбранныйУзел: УзелДерева? {
    guard let выбранныйИдентификатор else {
      return nil
    }
    return снимок?.узел(идентификатор: выбранныйИдентификатор)
  }

  var числоДокументов: Int {
    снимок?.числоДокументов ?? 0
  }

  var числоПропущенныхПутей: Int {
    снимок?.пропущенныеПути.count ?? 0
  }

  var имяУстройства: String {
    графическиеРесурсы?.устройство.name ?? "Metal недоступен"
  }

  func обновить() {
    задачаСканирования?.cancel()
    идётСканирование = true
    сообщениеОбОшибке = nil
    let корень = корень
    задачаСканирования = Task {
      let итог = await Task.detached(priority: .userInitiated) {
        do {
          return ИтогСканирования.готово(
            try СканерРепозитория().сканировать(корень: корень)
          )
        } catch {
          return ИтогСканирования.ошибка(error.localizedDescription)
        }
      }.value
      guard !Task.isCancelled else { return }
      применить(итог)
    }
  }

  private func применить(_ итог: ИтогСканирования) {
    идётСканирование = false
    switch итог {
    case .готово(let новыйСнимок):
      let допустимыеКаталоги = Set(
        новыйСнимок.узлы.lazy
          .filter { $0.вид != .документ }
          .map(\.id)
      )
      свёрнутыеИдентификаторы.formIntersection(допустимыеКаталоги)
      снимок = новыйСнимок
      раскладка = РаскладчикДерева().разложить(
        снимок: новыйСнимок,
        свёрнутые: свёрнутыеИдентификаторы
      )
      if let выбранныйИдентификатор,
        новыйСнимок.узел(идентификатор: выбранныйИдентификатор) == nil
      {
        self.выбранныйИдентификатор = nil
      }
      поколениеВписывания &+= 1
    case .ошибка(let сообщение):
      снимок = nil
      раскладка = nil
      выбранныйИдентификатор = nil
      сообщениеОбОшибке = сообщение
    }
  }

  func выбрать(_ идентификатор: String?) {
    выбранныйИдентификатор = идентификатор
  }

  func обработатьДвойнойЩелчок(_ идентификатор: String) {
    guard let узел = снимок?.узел(идентификатор: идентификатор) else {
      return
    }

    switch узел.вид {
    case .документ:
      let адрес = корень.appendingPathComponent(узел.относительныйПуть)
      NSWorkspace.shared.open(адрес)
    case .корень, .каталог:
      if свёрнутыеИдентификаторы.contains(идентификатор) {
        свёрнутыеИдентификаторы.remove(идентификатор)
      } else {
        свёрнутыеИдентификаторы.insert(идентификатор)
      }
      пересчитатьРаскладку()
    }
  }

  func вписать() {
    поколениеВписывания &+= 1
  }

  private func пересчитатьРаскладку() {
    guard let снимок else {
      return
    }
    раскладка = РаскладчикДерева().разложить(
      снимок: снимок,
      свёрнутые: свёрнутыеИдентификаторы
    )
  }
}

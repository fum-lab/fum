  @Test("один локальный сценарий связывает ответвления, цепочки, ревью и сборку")
  func полныйУправляемыйКонтурВоспроизводим() throws {
    let отчёт = try АвтономнаяПриёмкаПараллельныхУниверсальныхПодузлов.выполнить()

    #expect(отчёт.решение == .принято)
    #expect(отчёт.проверки.allSatisfy { $0.пройдена })
    #expect(
      Set(отчёт.проверки.map(\.идентификатор))
        == Set([
          "две-двухшаговые-ролевые-цепочки",
          "активация-и-единственность-владельцев",
          "освобождение-и-восстановление-модератора",
          "роли-не-расширяют-полномочия",
          "совместимость-перекрывается-конфликт-сериализуется",
          "раздельное-ревью-и-сравнительная-интеграция",
          "точный-конверт-предложения-и-транспорт-навыка",
          "синхронизация-ответвления-и-сравнительная-замена-сборки",
          "сбои-возобновляются-без-промежуточного-мусора",
          "повтор-и-свежие-клоны",
          "автономная-доказательная-граница",
        ]))

    #expect(отчёт.дочерниеЦепочки.count == 2)
    #expect(отчёт.дочерниеЦепочки.allSatisfy { $0.коммиты.count == 2 })
    #expect(Set(отчёт.дочерниеЦепочки.map(\.база)).count == 1)
    #expect(Set(отчёт.дочерниеЦепочки.map(\.идентификаторФорка)).count == 2)
    #expect(Set(отчёт.дочерниеЦепочки.map(\.идентификаторРепозитория)).count == 2)
    #expect(Set(отчёт.дочерниеЦепочки.map(\.рабочаяСсылка)).count == 2)
    #expect(Set(отчёт.дочерниеЦепочки.map(\.идентификаторРабочейКопии)).count == 2)
    #expect(Set(отчёт.дочерниеЦепочки.map(\.роль)).count == 2)
    #expect(Set(отчёт.дочерниеЦепочки.map(\.маршрут)).count == 2)
    #expect(Set(отчёт.дочерниеЦепочки.map(\.хэшПрофиляПолномочий)).count == 1)
    #expect(отчёт.родительскаяРабочаяКопияНеизменна)

    #expect(отчёт.допусковДоАктивации == 0)
    #expect(!отчёт.частичныйЗапускАктивировалПоколение)
    #expect(!отчёт.неизвестныйЗапускАктивировалПоколение)
    #expect(отчёт.максимумВладельцевОдногоРебёнка == 1)
    #expect(!отчёт.ожидающееПродолжениеУчтеноКакВторойВладелец)
    #expect(отчёт.дубликатДочернегоВладельцаОтклонён)
    #expect(отчёт.родительскаяСессияОсвобождена)
    #expect(отчёт.модераторВосстановленВНовомСеансе)
    #expect(!отчёт.модераторИзменилДочерниеСсылки)

    #expect(отчёт.максимумСовместимыхЗапусков == 2)
    #expect(отчёт.максимумКонфликтующихЗапусков == 1)
    #expect(Set(отчёт.ревью.map(\.исход)) == Set([.принято, .наДоработку]))
    #expect(отчёт.ревью.allSatisfy { $0.точнаяВершина })
    #expect(
      Set(отчёт.проверенныеОтрицательныеОгражденияРевью)
        == Set([
          "база_сдвинута",
          "вершина_сдвинута",
          "критерии_сдвинуты",
          "проверяющий_не_независим",
          "запрос_слияния_не_действителен",
        ]))
    #expect(отчёт.конвертыПредложений.count == 2)
    #expect(отчёт.конвертыПредложений.allSatisfy { $0.полныйДиапазон.count == 2 })
    #expect(отчёт.движениеГраницыАннулировалоРевью)

    #expect(
      отчёт.сагаСинхронизации.состояния == [
        "принято_в_ядре_синхронизация_ребёнка_ожидается",
        "согласование_ссылок_сборки_ожидается",
        "завершено",
      ])
    #expect(
      отчёт.сагаСинхронизации.принятаяВершинаЯдра
        == отчёт.сагаСинхронизации.зеркальнаяВершинаЯдра)
    #expect(
      отчёт.сагаСинхронизации.дочерняяВершина
        != отчёт.сагаСинхронизации.вершинаПредложения)
    #expect(отчёт.сагаСинхронизации.дочерняяВершинаПотомокЯдра)
    #expect(
      отчёт.сагаСинхронизации.ссылкаПодмодуляЯдра
        == отчёт.сагаСинхронизации.принятаяВершинаЯдра)
    #expect(
      отчёт.сагаСинхронизации.ссылкаПодмодуляРебёнка
        == отчёт.сагаСинхронизации.дочерняяВершина)
    #expect(отчёт.сагаСинхронизации.числоСравнительныхЗаменСборки == 1)
    #expect(отчёт.принятыйАртефактПрочитанНовымАгентом)

    #expect(
      Set(отчёт.проверенныеТочкиСбоев)
        == Set([
          "запуск",
          "шаг",
          "создание-предложения",
          "авторитетное-чтение-предложения",
          "ревью",
          "интеграция",
          "синхронизация-форка",
          "сборочная-ссылка-подмодуля",
        ]))
    #expect(отчёт.промежуточныеФайлыУчтены)
    #expect(отчёт.точныйПовторПослеУспешнойСравнительнойЗамены)
    #expect(
      отчёт.состояниеВозобновленияПослеСравнительнойЗамены
        == "цель_продвинута_следующий_переход_ожидается:"
        + отчёт.сагаСинхронизации.принятаяВершинаЯдра)

    #expect(отчёт.первыйХэшПаспорта == отчёт.повторныйХэшПаспорта)
    #expect(отчёт.первыйХэшДиагностики == отчёт.повторныйХэшДиагностики)
    #expect(отчёт.первыеИтоговыеДеревья == отчёт.повторныеИтоговыеДеревья)
    #expect(отчёт.свежиеКлоныВосстановилиОтсоединённыеСнимки)
    #expect(отчёт.свежиеКлоныВосстановилиСобственныеОчереди)
    #expect(отчёт.запрещённыеЭффекты.isEmpty)
    #expect(
      отчёт.границаДоказательства
        == "Локальный синтетический транспорт без сети, модели, секретов, внешней публикации и реальных задач среды; полезность навыка и реализация fum-optimizator не заявлены."
    )
  }
}

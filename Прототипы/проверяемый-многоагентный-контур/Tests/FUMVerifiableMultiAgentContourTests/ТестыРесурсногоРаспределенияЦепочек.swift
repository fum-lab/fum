  @Test("Канонический хэш зависит от всех структурированных ограждений, но не от порядка множеств")
  func каноническийХэшСтруктурированногоНазначения() throws {
    let исходное = назначение(
      идентификатор: "назначение-А",
      ссылка: "refs/heads/codex/ветвь-А",
      области: [точная("Документация/44.md"), поддерево("Прототипы/узел")],
      ресурсы: [ресурс(.внешняяСлужба, "служба-А"), ресурс(.секрет, "секрет-А")],
      эффекты: [.локальнаяЗапись, .созданиеДочернейЗадачи]
    )
    let переставленное = назначение(
      идентификатор: "назначение-А",
      ссылка: "refs/heads/codex/ветвь-А",
      области: [поддерево("Прототипы/узел"), точная("Документация/44.md")],
      ресурсы: [ресурс(.секрет, "секрет-А"), ресурс(.внешняяСлужба, "служба-А")],
      эффекты: [.созданиеДочернейЗадачи, .локальнаяЗапись]
    )
    let инаяРоль = назначение(
      идентификатор: "назначение-А",
      ссылка: "refs/heads/codex/ветвь-А",
      роль: "модератор результата",
      области: [точная("Документация/44.md"), поддерево("Прототипы/узел")],
      ресурсы: [ресурс(.внешняяСлужба, "служба-А"), ресурс(.секрет, "секрет-А")],
      эффекты: [.локальнаяЗапись, .созданиеДочернейЗадачи]
    )


      }

      let точное = назначение(из: ветвь)
      #expect(точное.идентификатор != точное.корневоеНазначение)
      #expect(точное.корневоеНазначение == ветвь.назначение)
      #expect(
        try реестр.зарегистрироватьРесурсноеНазначение(точное)

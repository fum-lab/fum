private final class КонкурентнаяФикстураЗахватаДочернейСессии: @unchecked Sendable {
  private let реестр: КорневойРеестрЗапусков
  private let свидетельства: [СвидетельствоЗахватаДочернейРесурснойСессии]
  private let блокировка = NSLock()
  private var успехи = 0
  private var кодыОтказов: [String] = []

  init(
    реестр: КорневойРеестрЗапусков,
    свидетельства: [СвидетельствоЗахватаДочернейРесурснойСессии]
  ) {
    self.реестр = реестр
    self.свидетельства = свидетельства
  }

  func выполнить() -> (успехи: Int, кодыОтказов: [String]) {
    DispatchQueue.concurrentPerform(iterations: свидетельства.count) { индекс in
      do {
        _ = try реестр.захватитьДочернююРесурснуюСессию(свидетельства[индекс])
        блокировка.withLock { успехи += 1 }

  @Test("Писатель и модератор одного fork делят один слот, а отдельные состояния не подменяются")
  func ограждённыеСчётчикиИСостояния() throws {
    try сРеестром { реестр in
      let писатель = назначение(
        идентификатор: "назначение-писателя",
        ссылка: "refs/heads/codex/писатель",
        области: [поддерево("Область/писателя")],
        классСессии: .писатель
      )
      let модератор = назначение(
        идентификатор: "назначение-модератора",
        поколение: "поколение-модератора",
        ребёнок: "ребёнок-модератора",
        ссылка: "refs/heads/codex/модератор",
        рабочаяКопия: "checkout-модератора",
        общийКаталог: "git-модератора",
        области: [поддерево("Область/модератора")],
        классСессии: .модератор
      )
      _ = try реестр.зарегистрироватьРесурсноеНазначение(писатель)
      _ = try реестр.зарегистрироватьРесурсноеНазначение(модератор)
      let допускПисателя = try реестр.запроситьРесурсныйДопуск(
        назначение: писатель.идентификатор,
        попытка: "попытка-писателя",
        ожидаемыйХэшНазначения: try писатель.каноническийХэш()
      )
      let ожиданиеМодератора = try реестр.запроситьРесурсныйДопуск(
        назначение: модератор.идентификатор,
        попытка: "попытка-модератора",
        ожидаемыйХэшНазначения: try модератор.каноническийХэш()
      )
      #expect(допускПисателя.состояние == .зарезервирована)
      #expect(ожиданиеМодератора.состояние == .ожидаетРесурсы)

      let неактивный = try реестр.изменитьСостояниеРесурснойСессии(
        попытка: "попытка-писателя",
        хэшДопуска: try #require(допускПисателя.хэшДопуска),
        новоеСостояние: .неактивныйРебёнок
      )
      #expect(неактивный.состояние == .неактивныйРебёнок)
      let ожиданиеПродолжения = try реестр.изменитьСостояниеРесурснойСессии(
        попытка: "попытка-писателя",
        хэшДопуска: try #require(допускПисателя.хэшДопуска),
        новоеСостояние: .ожидаетПродолжение
      )
      #expect(ожиданиеПродолжения.состояние == .ожидаетПродолжение)
      #expect(
        try реестр.восстановитьРесурсноеРешение(попытка: "попытка-модератора").состояние
          == .зарезервирована
      )

      let снимок = try реестр.снимокРесурсногоРаспределения()
      #expect(снимок.состояния["попытка-писателя"] == .ожидаетПродолжение)
      #expect(снимок.состояния["попытка-модератора"] == .зарезервирована)
      #expect(снимок.счётчики.владельцыФорков["fork-А"] == 1)
    }
  }


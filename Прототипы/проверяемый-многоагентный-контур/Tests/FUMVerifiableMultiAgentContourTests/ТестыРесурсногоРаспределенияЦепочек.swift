    #expect(try исходное.каноническийХэш() != инаяРоль.каноническийХэш())

    #expect(
      кодОшибки {
        _ = try назначение(
          идентификатор: "назначение-путь",
          ссылка: "refs/heads/codex/ветвь-путь",
          области: [точная("../секрет")]
        ).каноническийХэш()
      } == "неизвестная_совместимость_области")

import Foundation
import Testing

@testable import FUMVerifiableMultiAgentContour

@Suite("Исполнение корневой интеграции цепочки в локальных bare-репозиториях", .serialized)
struct ТестыИсполненияКорневойИнтеграцииЦепочки {
  @Test("Разрешение нельзя подделать публичным декодированием")
  func разрешениеНеДекодируется() {
    #expect(!(РазрешениеКорневойИнтеграцииЦепочки.self is any Decodable.Type))
  }

  @Test("Точный диапазон продвигается CAS без переписывания и точно повторяется")
  func точныйДиапазонИнтегрируетсяИдемпотентно() throws {
    let стенд = try СтендИсполненияКорневойИнтеграции()
    defer { стенд.удалить() }
    let разрешение = try разрешениеВалидатора(
      стенд, цель: стенд.перваяЦель)
    let запрос = запрос(стенд, разрешение, стенд.перваяЦель)
    let исполнитель = ИсполнительКорневойИнтеграцииЦепочки(
      исполняемыйФайлГит: стенд.исполняемыйФайлГит)

    let первый = try исполнитель.исполнить(запрос)

    #expect(первый.исход == .интегрировано)
    #expect(первый.ожидаемаяВершина == стенд.база)
    #expect(первый.наблюдаемаяВершина == стенд.вершина)
    #expect(первый.новаяВершина == стенд.вершина)
    #expect(первый.кандидатыСохранены)
    #expect(try стенд.вершинаСсылки("refs/heads/master", в: стенд.перваяЦель) == стенд.вершина)
    #expect(
      try стенд.диапазон(от: стенд.база, до: стенд.вершина, в: стенд.перваяЦель)
        == [стенд.середина, стенд.вершина])
    #expect(try стенд.родители(стенд.середина, в: стенд.перваяЦель) == [стенд.база])
    #expect(try стенд.родители(стенд.вершина, в: стенд.перваяЦель) == [стенд.середина])
    #expect(try стенд.являетсяПредком(стенд.середина, для: стенд.вершина, в: стенд.перваяЦель))

    let повтор = try исполнитель.исполнить(запрос)
    #expect(повтор.исход == .ужеИнтегрировано)
    #expect(повтор.наблюдаемаяВершина == стенд.вершина)
  }

  @Test("Сдвиг цели перед CAS не теряет переданных кандидатов")
  func сдвигЦелиСохраняетКандидатов() throws {
    let стенд = try СтендИсполненияКорневойИнтеграции()
    defer { стенд.удалить() }
    let разрешение = try разрешениеВалидатора(
      стенд, цель: стенд.перваяЦель)
    let перехваты = ПерехватыИсполненияКорневойИнтеграцииЦепочки(
      передСравнениемИЗаменой: {
        try стенд.установитьСсылку(
          "refs/heads/master",
          в: стенд.перваяЦель,
          на: стенд.середина,
          ожидая: стенд.база
        )
      }
    )
    let исполнитель = ИсполнительКорневойИнтеграцииЦепочки(
      исполняемыйФайлГит: стенд.исполняемыйФайлГит,
      перехваты: перехваты
    )

    let результат = try исполнитель.исполнить(
      запрос(стенд, разрешение, стенд.перваяЦель))

    #expect(результат.исход == .цельСдвинута)
    #expect(результат.наблюдаемаяВершина == стенд.середина)
    #expect(результат.кандидатыСохранены)
    #expect(try стенд.вершинаСсылки("refs/heads/master", в: стенд.перваяЦель) == стенд.середина)
    #expect(try стенд.кандидатУдержан(стенд.вершина, в: стенд.перваяЦель))
  }

  @Test("Потеря ответа после CAS восстанавливается авторитетным чтением")
  func потерянныйОтветВосстанавливаетсяЧтением() throws {
    let стенд = try СтендИсполненияКорневойИнтеграции()
    defer { стенд.удалить() }
    let разрешение = try разрешениеВалидатора(
      стенд, цель: стенд.втораяЦель)
    let перехваты = ПерехватыИсполненияКорневойИнтеграцииЦепочки(
      послеСравненияИЗамены: {
        try стенд.установитьСсылку(
          "refs/heads/master",
          в: стенд.втораяЦель,
          на: стенд.середина,
          ожидая: стенд.вершина
        )
        throw ОшибкаСтендаКорневойИнтеграции.потерянныйОтвет
      }
    )
    let исполнитель = ИсполнительКорневойИнтеграцииЦепочки(
      исполняемыйФайлГит: стенд.исполняемыйФайлГит,
      перехваты: перехваты
    )

    let результат = try исполнитель.исполнить(
      запрос(стенд, разрешение, стенд.втораяЦель))

    #expect(результат.исход == .цельСдвинута)
    #expect(результат.наблюдаемаяВершина == стенд.середина)
    #expect(результат.кандидатыСохранены)
    #expect(try стенд.вершинаСсылки("refs/heads/master", в: стенд.втораяЦель) == стенд.середина)
    #expect(try стенд.кандидатУдержан(стенд.вершина, в: стенд.втораяЦель))
  }

  @Test("Разрешение нельзя повторить в другом исходном, целевом репозитории или ref")
  func разрешениеСвязаноСПутямиИСсылкой() throws {
    let стенд = try СтендИсполненияКорневойИнтеграции()
    defer { стенд.удалить() }
    try стенд.установитьСсылку(
      "refs/heads/повтор", в: стенд.исходныйРепозиторий, на: стенд.вершина)
    let разрешение = try разрешениеВалидатора(
      стенд, цель: стенд.перваяЦель)
    let исполнитель = ИсполнительКорневойИнтеграцииЦепочки(
      исполняемыйФайлГит: стенд.исполняемыйФайлГит)

    let другойИсточник = try исполнитель.исполнить(
      запрос(
        стенд,
        разрешение,
        стенд.перваяЦель,
        исходныйРепозиторий: стенд.втораяЦель
      ))
    let другаяЦель = try исполнитель.исполнить(
      запрос(стенд, разрешение, стенд.втораяЦель))
    let другаяСсылка = try исполнитель.исполнить(
      запрос(
        стенд,
        разрешение,
        стенд.перваяЦель,
        исходнаяСсылка: "refs/heads/повтор"
      ))

    #expect(другойИсточник.исход == .диапазонНедействителен)
    #expect(другаяЦель.исход == .диапазонНедействителен)
    #expect(другаяСсылка.исход == .диапазонНедействителен)
    #expect(
      try стенд.вершинаСсылки("refs/heads/master", в: стенд.перваяЦель)
        == стенд.база)
    #expect(
      try стенд.вершинаСсылки("refs/heads/master", в: стенд.втораяЦель)
        == стенд.база)
  }

}

private func запрос(
  _ стенд: СтендИсполненияКорневойИнтеграции,
  _ разрешение: РазрешениеКорневойИнтеграцииЦепочки,
  _ цель: URL,
  исходныйРепозиторий: URL? = nil,
  исходнаяСсылка: String? = "refs/heads/master"
) -> ЗапросИсполненияКорневойИнтеграцииЦепочки {
  ЗапросИсполненияКорневойИнтеграцииЦепочки(
    разрешение: разрешение,
    исходныйРепозиторий: исходныйРепозиторий ?? стенд.исходныйРепозиторий,
    целевойРепозиторий: цель,
    исходнаяСсылка: исходнаяСсылка
  )
}

private func разрешениеВалидатора(
  _ стенд: СтендИсполненияКорневойИнтеграции,
  цель: URL,
  исходнаяСсылка: String = "refs/heads/master"
) throws -> РазрешениеКорневойИнтеграцииЦепочки {
  let база = стенд.база
  let вершина = стенд.вершина
  let коммиты = стенд.линейныеКоммиты
  let путьИсточника = стенд.исходныйРепозиторий
    .standardizedFileURL.resolvingSymlinksInPath().path
  let путьЦели = цель.standardizedFileURL.resolvingSymlinksInPath().path
  let хэшиПаспортов = Array("123456789abcdef").prefix(коммиты.count).map(хэш)
  let снимок = СнимокКорневогоРевьюИИнтеграцииЦепочки(
    паспортРевью: ПаспортКорневогоРевьюЦепочки(
      идентификатор: "review.execution.1",
      поколениеНазначения: "assignment.1",
      проверяющий: "fork.reviewer",
      поставщик: "fork.supplier",
      интегратор: "fork.integrator",
      маршрут: .собственныйРезультатРебёнка,
      исходныйРепозиторий: "repository.child",
      целевойРепозиторий: "repository.child",
      целеваяСсылка: "refs/heads/master",
      база: база,
      вершина: вершина,
      коммиты: коммиты,
      хэшиЧастныхПаспортов: хэшиПаспортов,
      хэшКритериев: хэш("a"),
      первоначальныеПроверки: [хэш("b")],
      повторныеПроверки: [хэш("b")],
      замечания: [
        ЗамечаниеКорневогоРевьюЦепочки(
          код: "range.checked",
          путь: "Tests/",
          сообщение: "Границы проверены.",
          группаКорреляции: "range-evidence"
        )
      ],
      группыКорреляции: ["range-evidence"],
      исход: .принято,
      каноническийПутьИсходногоРепозитория: путьИсточника,
      каноническийПутьЦелевогоРепозитория: путьЦели,
      исходнаяСсылка: исходнаяСсылка
    ),
    паспортМодерации: nil,
    конвертЗапросаСлияния: nil,
    режимПринятия: .всяЦепочка,
    принятаяВершина: вершина,
    исходноеПоколениеКандидата: "candidate.1",
    исходнаяСсылкаКандидата: исходнаяСсылка,
    исходныйХэшПаспортаКандидата: хэш("c"),
    новоеПоколениеКандидата: nil,
    новаяСсылкаКандидата: nil,
    новыйХэшПаспортаКандидата: nil,
    новыйКонвертПрефикса: nil,
    новоеПоколениеДоработки: nil,
    актуальноеПоколениеНазначения: "assignment.1",
    актуальнаяБаза: база,
    актуальнаяВершина: вершина,
    актуальныеХэшиЧастныхПаспортов: хэшиПаспортов,
    актуальныйХэшКритериев: хэш("a"),
    актуальнаяЦелеваяСсылка: "refs/heads/master",
    актуальнаяВершинаЦели: база,
    каноническийПутьИсходногоРепозитория: путьИсточника,
    каноническийПутьЦелевогоРепозитория: путьЦели
  )
  let отчёт = ПроверкаКорневогоРевьюИИнтеграцииЦепочки.проверить(снимок)
  #expect(отчёт.кодыНарушений.isEmpty)
  let разрешение = try #require(отчёт.разрешение)
  #expect(разрешение.хэшПаспортаРевью == (try снимок.паспортРевью.каноническийХэш()))
  return разрешение
}

private final class СтендИсполненияКорневойИнтеграции: @unchecked Sendable {
  let корень: URL
  let исполняемыйФайлГит = WritingSubnodeSystemRuntime.gitExecutableURL
  let исходныйРепозиторий: URL
  let перваяЦель: URL
  let втораяЦель: URL
  let база: String
  let середина: String
  let вершина: String

  var линейныеКоммиты: [КоммитПринятогоДиапазонаЦепочки] {
    [
      КоммитПринятогоДиапазонаЦепочки(объект: середина, родители: [база]),
      КоммитПринятогоДиапазонаЦепочки(объект: вершина, родители: [середина]),
    ]
  }

  init() throws {
    let файловаяСистема = FileManager.default
    let корень = файловаяСистема.temporaryDirectory.appendingPathComponent(
      "fum-root-integration-\(UUID().uuidString)", isDirectory: true)
    self.корень = корень
    исходныйРепозиторий = корень.appendingPathComponent("source.git", isDirectory: true)
    перваяЦель = корень.appendingPathComponent("target-one.git", isDirectory: true)
    втораяЦель = корень.appendingPathComponent("target-two.git", isDirectory: true)
    let рабочаяКопия = корень.appendingPathComponent("work", isDirectory: true)

    try файловаяСистема.createDirectory(at: корень, withIntermediateDirectories: true)
    for репозиторий in [исходныйРепозиторий, перваяЦель, втораяЦель] {
      _ = try Self.выполнить(
        ["init", "--quiet", "--bare", "--initial-branch=master", "--", репозиторий.path],
        в: корень
      )
    }
    _ = try Self.выполнить(
      ["init", "--quiet", "--initial-branch=master", "--", рабочаяКопия.path],
      в: корень
    )
    _ = try Self.выполнить(["config", "user.name", "FUM Test"], в: рабочаяКопия)
    _ = try Self.выполнить(["config", "user.email", "fum-test@example.invalid"], в: рабочаяКопия)

    try Self.записать("база\n", в: рабочаяКопия, путь: "chain.txt")
    try Self.зафиксировать("база", в: рабочаяКопия)
    база = try Self.выполнить(["rev-parse", "HEAD"], в: рабочаяКопия)
    try Self.записать("середина\n", в: рабочаяКопия, путь: "chain.txt")
    try Self.зафиксировать("середина", в: рабочаяКопия)
    середина = try Self.выполнить(["rev-parse", "HEAD"], в: рабочаяКопия)
    try Self.записать("вершина\n", в: рабочаяКопия, путь: "chain.txt")
    try Self.зафиксировать("вершина", в: рабочаяКопия)
    вершина = try Self.выполнить(["rev-parse", "HEAD"], в: рабочаяКопия)

    _ = try Self.выполнить(
      ["push", "--quiet", исходныйРепозиторий.path, "master:refs/heads/master"], в: рабочаяКопия)
    for цель in [перваяЦель, втораяЦель] {
      _ = try Self.выполнить(
        ["push", "--quiet", цель.path, "\(база):refs/heads/master"], в: рабочаяКопия)
    }
  }

  func удалить() { try? FileManager.default.removeItem(at: корень) }

  func вершинаСсылки(_ ссылка: String, в репозиторий: URL) throws -> String {
    try Self.выполнить(["rev-parse", "--verify", "\(ссылка)^{commit}"], в: репозиторий)
  }

  func диапазон(от база: String, до вершина: String, в репозиторий: URL) throws -> [String] {
    try Self.выполнить(["rev-list", "--reverse", "\(база)..\(вершина)"], в: репозиторий)
      .split(separator: "\n").map(String.init)
  }

  func родители(_ объект: String, в репозиторий: URL) throws -> [String] {
    let поля = try Self.выполнить(["rev-list", "--parents", "-n", "1", объект], в: репозиторий)
      .split(separator: " ").map(String.init)
    return Array(поля.dropFirst())
  }

  func являетсяПредком(_ предок: String, для потомок: String, в репозиторий: URL) throws -> Bool {
    _ = try Self.выполнить(["merge-base", "--is-ancestor", предок, потомок], в: репозиторий)
    return true
  }

  func кандидатУдержан(_ объект: String, в репозиторий: URL) throws -> Bool {
    let ссылки = try Self.выполнить(
      ["for-each-ref", "--format=%(refname)", "--points-at", объект, "refs/fum/"],
      в: репозиторий
    )
    return !ссылки.isEmpty
  }

  func установитьСсылку(
    _ ссылка: String,
    в репозиторий: URL,
    на новаяВершина: String,
    ожидая стараяВершина: String? = nil
  ) throws {
    var аргументы = ["update-ref", ссылка, новаяВершина]
    if let стараяВершина { аргументы.append(стараяВершина) }
    _ = try Self.выполнить(аргументы, в: репозиторий)
  }

  private static func записать(_ текст: String, в каталог: URL, путь: String) throws {
    try Data(текст.utf8).write(to: каталог.appendingPathComponent(путь))
  }

  private static func зафиксировать(_ сообщение: String, в каталог: URL) throws {
    _ = try выполнить(["add", "--all"], в: каталог)
    _ = try выполнить(["commit", "--quiet", "-m", сообщение], в: каталог)
  }

  @discardableResult
  private static func выполнить(_ аргументы: [String], в каталог: URL) throws -> String {
    let процесс = Process()
    процесс.executableURL = WritingSubnodeSystemRuntime.gitExecutableURL
    процесс.arguments =
      [
        "--no-replace-objects", "-c",
        "core.hooksPath=\(WritingSubnodeSystemRuntime.nullDevicePath)",
      ] + аргументы
    процесс.currentDirectoryURL = каталог
    процесс.environment = [
      "GIT_CONFIG_NOSYSTEM": "1",
      "GIT_CONFIG_GLOBAL": WritingSubnodeSystemRuntime.nullDevicePath,
      "GIT_TERMINAL_PROMPT": "0", "LC_ALL": "C",
      "PATH": ProcessInfo.processInfo.environment["PATH"]
        ?? WritingSubnodeSystemRuntime.gitExecutableURL.deletingLastPathComponent().path,
    ]
    let вывод = Pipe()
    процесс.standardOutput = вывод
    процесс.standardError = вывод
    try процесс.run()
    try вывод.fileHandleForWriting.close()
    let данные = вывод.fileHandleForReading.readDataToEndOfFile()
    процесс.waitUntilExit()
    let текст = String(decoding: данные, as: UTF8.self)
      .trimmingCharacters(in: .whitespacesAndNewlines)
    guard процесс.terminationStatus == 0 else {
      throw ОшибкаСтендаКорневойИнтеграции.команда(текст)
    }
    return текст
  }
}

private enum ОшибкаСтендаКорневойИнтеграции: Error {
  case команда(String)
  case потерянныйОтвет
}

private func хэш(_ знак: Character) -> String {
  "sha256:" + String(repeating: знак, count: 64)
}

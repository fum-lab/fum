import Foundation
import Testing

@testable import FUMVerifiableMultiAgentContour

@Suite("Корневой реестр запусков ветвевых fork")
struct ТестыКорневогоРеестраЗапусков {
  @Test("Точная пара задач активируется одним CAS и только после него входит в FIFO")
  func точнаяПараАктивируетсяАтомарно() throws {
    let итог = try ФикстурыКорневогоРеестраЗапусков.каноническаяПара()

    #expect(итог.кодОтказа == nil)
    #expect(итог.числоВызововСреды == 2)
    #expect(итог.числоАктиваций == 1)
    #expect(итог.допущенныеСтороны == Set([.левая, .правая]))
    #expect(итог.идентификаторыЗадач.count == 2)
    #expect(Set(итог.идентификаторыЗадач).count == 2)
    #expect(итог.идентификаторыОбщихКаталогов.count == 2)
    #expect(Set(итог.идентификаторыОбщихКаталогов).count == 2)
    #expect(!итог.переносимыйПаспорт.contains(итог.машинноЛокальныйКорень))
  }

  @Test("Потеря первого ответа запрещает второй вызов, повтор и запись обоих детей")
  func потерянныйОтветНеСоздаётЗамену() throws {
    let итог = try ФикстурыКорневогоРеестраЗапусков.потерянныйПервыйОтвет()

    #expect(итог.кодОтказа == "неизвестный_ответ_среды")
    #expect(итог.числоВызововСреды == 1)
    #expect(итог.числоАктиваций == 0)
    #expect(итог.допущенныеСтороны.isEmpty)
    #expect(итог.состоянияПопыток[.левая] == .неизвестна)
    #expect(итог.состоянияПопыток[.правая] == .подготовлена)
  }

  @Test("Падение после долговечного намерения блокирует повтор и соседнюю сторону")
  func незавершённоеНамерениеБлокируетПару() throws {
    let итог = try ФикстурыКорневогоРеестраЗапусков.падениеПослеНамерения()

    #expect(итог.кодОтказа == "неразрешённая_попытка_блокирует_вызов")
    #expect(итог.числоВызововСреды == 0)
    #expect(итог.состоянияПопыток[.левая] == .вызовНачат)
    #expect(итог.состоянияПопыток[.правая] == .подготовлена)
    #expect(итог.допущенныеСтороны.isEmpty)
  }

  @Test("Точное восстановление старой попытки не подтверждает вторую сторону")
  func восстановлениеОгражденоСторонойИПопыткой() throws {
    let точный = try ФикстурыКорневогоРеестраЗапусков.точноеВосстановление()
    #expect(точный.состоянияПопыток[.левая] == .подтверждена)
    #expect(точный.состоянияПопыток[.правая] == .неизвестна)
    #expect(точный.допущенныеСтороны.isEmpty)

    let чужой = try ФикстурыКорневогоРеестраЗапусков.чужоеВосстановление()
    #expect(чужой.кодОтказа == "несовпавший_авторитетный_результат")
    #expect(чужой.числоВызововСреды == 1)
    #expect(чужой.допущенныеСтороны.isEmpty)
  }

  @Test("Восстановление принимает ровно один авторитетно прочитанный exact-результат")
  func восстановлениеТребуетЕдинственногоТочногоЧтения() throws {
    let ноль = try ФикстурыКорневогоРеестраЗапусков.пустоеАвторитетноеВосстановление()
    #expect(ноль.кодОтказа == "авторитетный_результат_не_единственный")
    #expect(ноль.состоянияПопыток[.левая] == .неизвестна)

    let несколько = try ФикстурыКорневогоРеестраЗапусков.множественноеАвторитетноеВосстановление()
    #expect(несколько.кодОтказа == "авторитетный_результат_не_единственный")
    #expect(несколько.состоянияПопыток[.левая] == .неизвестна)
    #expect(несколько.идентификаторыЗадач == ["task.left", "task.other"])
    #expect(несколько.идентификаторыСред == ["host.left", "host.other"])

    let подмена = try ФикстурыКорневогоРеестраЗапусков.несовпавшееАвторитетноеВосстановление()
    #expect(подмена.кодОтказа == "несовпавший_авторитетный_результат")
    #expect(подмена.состоянияПопыток[.левая] == .неизвестна)
  }

  @Test("Неполный ответ и несовпавший CODEX_THREAD_ID закрывают привязку")
  func точнаяПривязкаОбязательна() throws {
    let неполный = try ФикстурыКорневогоРеестраЗапусков.неполныйОтвет()
    #expect(неполный.кодОтказа == "неполный_ответ_среды")
    #expect(неполный.допущенныеСтороны.isEmpty)

    let подмена = try ФикстурыКорневогоРеестраЗапусков.подменаИдентификатораСеанса()
    #expect(подмена.кодОтказа == "несовпавший_CODEX_THREAD_ID")
    #expect(подмена.допущенныеСтороны.isEmpty)

    let среда = try ФикстурыКорневогоРеестраЗапусков.подменаСредыБилета()
    #expect(среда.кодОтказа == "несовпавший_неактивный_билет")

    let вершина = try ФикстурыКорневогоРеестраЗапусков.подменаВершиныБилета()
    #expect(вершина.кодОтказа == "несовпавший_неактивный_билет")

    let неполныйТочный = try ФикстурыКорневогоРеестраЗапусков.неполныйТочныйОтвет()
    #expect(неполныйТочный.кодОтказа == "неполный_ответ_среды")
    #expect(неполныйТочный.состоянияПопыток[.левая] == .неизвестна)
    #expect(неполныйТочный.идентификаторыЗадач == ["task.incomplete"])
  }

  @Test("Межпоколенческий реестр навсегда резервирует пару repo/ref и живую рабочую копию")
  func межпоколенческиеРезервыНеПереиспользуются() throws {
    let повторПары = try ФикстурыКорневогоРеестраЗапусков.повторРабочейПарыВНовомПоколении()
    #expect(повторПары.кодОтказа == "рабочая_пара_уже_зарезервирована")

    let повторКопии = try ФикстурыКорневогоРеестраЗапусков.повторРабочейКопииВНовомПоколении()
    #expect(повторКопии.кодОтказа == "рабочая_копия_уже_зарезервирована")

    let общийКаталог = try ФикстурыКорневогоРеестраЗапусков.общийКаталогДвухКлонов()
    #expect(общийКаталог.кодОтказа == "рабочая_копия_не_автономна")

    let повторФорка = try ФикстурыКорневогоРеестраЗапусков.повторФоркаВНовомПоколении()
    #expect(повторФорка.кодОтказа == "форк_уже_зарезервирован")

    let повторПопытки = try ФикстурыКорневогоРеестраЗапусков.повторПопыткиВНовомПоколении()
    #expect(повторПопытки.кодОтказа == "попытка_уже_зарезервирована")

    let псевдонимИсточника = try ФикстурыКорневогоРеестраЗапусков.псевдонимФизическогоИсточника()
    #expect(псевдонимИсточника.кодОтказа == "физический_источник_уже_зарезервирован")

    let псевдонимКопии = try ФикстурыКорневогоРеестраЗапусков.псевдонимФизическойРабочейКопии()
    #expect(псевдонимКопии.кодОтказа == "физическая_рабочая_копия_уже_зарезервирована")
  }

  @Test("Одна Desktop-задача не может исполнять другой шаг или поколение")
  func задачаИСеансНеПереносятся() throws {
    let итог = try ФикстурыКорневогоРеестраЗапусков.повторЗадачиДляДругогоШага()
    #expect(итог.кодОтказа == "задача_среды_уже_связана")
    #expect(итог.идентификаторыЗадач.count == 1)
    #expect(итог.идентификаторыСред == ["host.one", "host.two"])
    #expect(итог.состоянияПопыток[.правая] == .неизвестна)
  }

  @Test("Конверт создания вычисляется из всех ограждений, а не принимается готовым")
  func конвертСозданияВычисленИПолон() throws {
    let итог = try ФикстурыКорневогоРеестраЗапусков.каноническаяПара()

    #expect(итог.конвертыСозданияПолны)
    #expect(итог.хэшиКонвертов.count == 2)
    #expect(
      итог.хэшиКонвертов.allSatisfy {
        $0.range(of: #"^sha256:[0-9a-f]{64}$"#, options: .regularExpression) != nil
      })
  }

  @Test("Падение после CAS восстанавливает одну квитанцию без новых задач")
  func квитанцияАктивацииИдемпотентна() throws {
    let итог = try ФикстурыКорневогоРеестраЗапусков.возобновлениеПослеАктивации()

    #expect(итог.кодОтказа == nil)
    #expect(итог.числоВызововСреды == 2)
    #expect(итог.числоАктиваций == 1)
    #expect(итог.хэшиКвитанций.count == 2)
    #expect(Set(итог.хэшиКвитанций).count == 1)
  }

  @Test("Позднее восстановление не изменяет замороженную или активированную пару")
  func позднееВосстановлениеНеИнвалидируетКвитанцию() throws {
    let итог = try ФикстурыКорневогоРеестраЗапусков.позднееВосстановлениеПослеАктивации()

    #expect(итог.кодОтказа == "поколение_уже_заморожено")
    #expect(итог.числоАктиваций == 1)
    #expect(итог.состоянияПопыток[.левая] == .подтверждена)
    #expect(итог.допущенныеСтороны == Set([.левая]))
    #expect(итог.хэшиПривязок.count == 2)
    #expect(Set(итог.хэшиПривязок).count == 2)
  }

  @Test("Замороженная нагрузка и повторная проверка клона ограждают активацию")
  func активацияПовторноПроверяетЗамороженнуюНагрузку() throws {
    let перепривязка = try ФикстурыКорневогоРеестраЗапусков.перепривязкаКлонаПослеЗаморозки()
    #expect(перепривязка.кодОтказа == "изменившийся_клон_перед_активацией")
    #expect(перепривязка.числоАктиваций == 0)
    #expect(перепривязка.допущенныеСтороны.isEmpty)

    let устаревшийХэш = try ФикстурыКорневогоРеестраЗапусков.устаревшийХэшЗаморозки()
    #expect(устаревшийХэш.кодОтказа == "устаревшее_ограждение_активации")
    #expect(устаревшийХэш.числоАктиваций == 0)
  }

  @Test("Недоступная идентичность Desktop-контроллера не превращается в доказанный singleton")
  func границаКонтроллераЧестная() throws {
    let итог = try ФикстурыКорневогоРеестраЗапусков.контроллерНедоступен()
    #expect(итог.идентичностьКонтроллера == .недоступна)
    #expect(!итог.единственностьКонтроллераДоказана)
    #expect(итог.числоВызововСреды == 2)

    let подмена = try ФикстурыКорневогоРеестраЗапусков.ложноДоказанныйКонтроллер()
    #expect(подмена.кодОтказа == "неподдержанная_идентичность_контроллера")
    #expect(!подмена.единственностьКонтроллераДоказана)
  }
}

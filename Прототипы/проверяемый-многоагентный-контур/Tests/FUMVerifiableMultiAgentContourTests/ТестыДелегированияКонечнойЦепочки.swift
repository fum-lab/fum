  private func обновитьХэш(
    _ исходный: [String: Any],
    поле: String
  ) throws -> [String: Any] {
    var результат = исходный
    результат.removeValue(forKey: поле)
    let каноническиеДанные = try данные(результат)
    результат[поле] =
      "sha256:"
      + SHA256.hash(data: каноническиеДанные).map {
        String(format: "%02x", $0)
      }.joined()
    return результат
  }

  private func изменить(
    _ исходный: [String: Any],
    путь: [String],
    на значение: Any
  ) throws -> [String: Any] {
    var результат = исходный
    try установить(&результат, путь: ArraySlice(путь), значение: значение)
    return результат
  }

  private func установить(
    _ объект: inout [String: Any],
    путь: ArraySlice<String>,
    значение: Any
  ) throws {
    let ключ = try #require(путь.first)
    if путь.count == 1 {
      объект[ключ] = значение
      return
    }
    var вложенный = try #require(объект[ключ] as? [String: Any])
    try установить(&вложенный, путь: путь.dropFirst(), значение: значение)
    объект[ключ] = вложенный
  }

  private func дополнитьМассив(
    _ исходный: [String: Any],
    путь: [String],
    значением значение: Any
  ) throws -> [String: Any] {
    let существующий = try значениеПоПути(исходный, путь: ArraySlice(путь))
    var массив = try #require(существующий as? [Any])
    массив.append(значение)
    return try изменить(исходный, путь: путь, на: массив)
  }

  private func значениеПоПути(
    _ объект: [String: Any],
    путь: ArraySlice<String>
  ) throws -> Any {
    let ключ = try #require(путь.first)
    let значение = try #require(объект[ключ])
    if путь.count == 1 { return значение }
    return try значениеПоПути(
      try #require(значение as? [String: Any]),
      путь: путь.dropFirst()
    )
  }

  private func объект(_ данные: Data) throws -> [String: Any] {
    try #require(JSONSerialization.jsonObject(with: данные) as? [String: Any])
  }

  private func данные(_ объект: [String: Any]) throws -> Data {
    try JSONSerialization.data(
      withJSONObject: объект,
      options: [.sortedKeys, .withoutEscapingSlashes]
    )
  }

  private func повтор(_ символ: Character = "b", длина: Int = 40) -> String {
    String(repeating: String(символ), count: длина)
  }

  @Test("Неоднозначный JSON и не-NFC строки отклоняются до хэширования")
  func повторныеКлючиИНенормализованныеСтрокиОтклоняются() throws {
    let фикстура = try ФикстурыДелегированияКонечнойЦепочки.каноническая()
    let исходныйТекст = try #require(String(data: фикстура.назначение, encoding: .utf8))
    let поле = "\"поколение_схемы\":1"
    let повторныйТекст = исходныйТекст.replacingOccurrences(
      of: поле,
      with: поле + "," + поле
    )
    let повторныйОтчёт = ПроверкаДелегированияКонечнойЦепочки.проверить(
      назначение: Data(повторныйТекст.utf8),
      состояние: фикстура.состояние,
      контекст: фикстура.контекст
    )
    #expect(повторныйОтчёт.кодыНарушений.contains("повторный_ключ"))

    let исходнаяРоль = "идентификатор_ребёнка"
    let ненормализованнаяРоль = исходнаяРоль.decomposedStringWithCanonicalMapping
    let ненормализованныйТекст = исходныйТекст.replacingOccurrences(
      of: исходнаяРоль,
      with: ненормализованнаяРоль
    )
    let ненормализованныйОтчёт = ПроверкаДелегированияКонечнойЦепочки.проверить(
      назначение: Data(ненормализованныйТекст.utf8),
      состояние: фикстура.состояние,
      контекст: фикстура.контекст
    )
    #expect(ненормализованныйОтчёт.кодыНарушений.contains("строка_не_NFC"))

    let схемаСПовтором = Data(
      "{\"$schema\":\"https://json-schema.org/draft/2020-12/schema\",\"$schema\":\"https://json-schema.org/draft/2020-12/schema\",\"type\":\"object\",\"additionalProperties\":false}"
        .utf8
    )
    #expect(
      ПроверкаЗакрытойСхемы.проверитьСхему(схемаСПовтором).map(\.код)
        .contains("повторный_ключ")
    )
  }


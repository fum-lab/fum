@testable import FUMVerifiableMultiAgentContour

@Suite("Закрытые схемы корневого ревью цепочки")
struct ТестыСхемКорневогоРевьюЦепочки {
  @Test("Три схемы v1 закрыты и принимают канонические Codable-документы")
  func схемыЗакрытыИПринимаютКаноническиеДокументы() throws {
    let документыИСхемы = [
      (
        try каноническиеДанные(каноническийПаспортРевью()),
        try СхемыКорневогоРевьюЦепочки.загрузитьПаспортРевью()
      ),
      (
        try каноническиеДанные(каноническийПаспортМодерации()),
        try СхемыКорневогоРевьюЦепочки.загрузитьПаспортМодерации()
      ),
      (
        try каноническиеДанные(каноническийКонвертЗапросаСлияния()),
        try СхемыКорневогоРевьюЦепочки.загрузитьКонвертЗапросаСлияния()
      ),
    ]

    for (данныеДокумента, схема) in документыИСхемы {
      #expect(ПроверкаЗакрытойСхемы.проверитьСхему(схема).isEmpty)
      let документ = try JSONSerialization.jsonObject(with: данныеДокумента)
      #expect(ПроверкаЗакрытойСхемы.проверитьДокумент(документ, по: схема).isEmpty)
    }
  }

  @Test("Неизвестное поле и неверные исходы отклоняются на границе схем")
  func неизвестноеПолеИНеверныеИсходыОтклоняются() throws {
    let документыИСхемы = [
      (
        try каноническиеДанные(каноническийПаспортРевью()),
        try СхемыКорневогоРевьюЦепочки.загрузитьПаспортРевью()
      ),
      (
        try каноническиеДанные(каноническийПаспортМодерации()),
        try СхемыКорневогоРевьюЦепочки.загрузитьПаспортМодерации()
      ),
      (
        try каноническиеДанные(каноническийКонвертЗапросаСлияния()),
        try СхемыКорневогоРевьюЦепочки.загрузитьКонвертЗапросаСлияния()
      ),
    ]
    for (данныеДокумента, схема) in документыИСхемы {
      var документ = try объектДокумента(данныеДокумента)
      документ["неизвестноеПоле"] = true
      #expect(!ПроверкаЗакрытойСхемы.проверитьДокумент(документ, по: схема).isEmpty)
    }

    let неверныеИсходы = [
      (
        try изменив(
          try каноническиеДанные(каноническийПаспортРевью()),
          поле: "исход",
          значение: "условно_принято"
        ),
        try СхемыКорневогоРевьюЦепочки.загрузитьПаспортРевью()
      ),
      (
        try изменив(
          try каноническиеДанные(каноническийПаспортМодерации()),
          поле: "решение",
          значение: "условно_объединено"
        ),
        try СхемыКорневогоРевьюЦепочки.загрузитьПаспортМодерации()
      ),
      (
        try изменив(
          try каноническиеДанные(каноническийКонвертЗапросаСлияния()),
          поле: "состояние",
          значение: "условно_открыт"
        ),
        try СхемыКорневогоРевьюЦепочки.загрузитьКонвертЗапросаСлияния()
      ),
    ]
    for (документ, схема) in неверныеИсходы {
      #expect(!ПроверкаЗакрытойСхемы.проверитьДокумент(документ, по: схема).isEmpty)
    }
  }

  @Test("Runtime-декодер совпадает со схемой и отвергает неизвестные и повторные поля")
  func строгоеДекодированиеНеОслабляетЗакрытуюСхему() throws {
    let канонические = try каноническийПаспортРевью().каноническиеДанные()
    #expect(
      try СхемыКорневогоРевьюЦепочки.декодироватьПаспортРевью(канонические)
        == каноническийПаспортРевью())

    var неизвестное = try объектДокумента(канонические)
    var значение = try #require(неизвестное["значение"] as? [String: Any])
    значение["неизвестноеПоле"] = true
    неизвестное["значение"] = значение
    let данныеСНеизвестным = try JSONSerialization.data(
      withJSONObject: неизвестное, options: [.sortedKeys])
    let схема = try СхемыКорневогоРевьюЦепочки.загрузитьПаспортРевью()
    #expect(
      ПроверкаЗакрытойСхемы.проверитьДокумент(
        try JSONSerialization.data(withJSONObject: значение, options: [.sortedKeys]),
        по: схема
      ).contains { $0.код == "неизвестное_поле" })
    #expect(
      кодыСтрогогоОтказа {
        _ = try СхемыКорневогоРевьюЦепочки.декодироватьПаспортРевью(
          данныеСНеизвестным)
      }.contains("неизвестное_поле"))

    let текст = String(decoding: канонические, as: UTF8.self)
    let повторВерсии = Data(
      текст.replacingOccurrences(
        of: "{", with: "{\"версияСхемы\":1,", options: [],
        range: текст.startIndex..<текст.index(after: текст.startIndex)
      ).utf8)
    #expect(
      кодыСтрогогоОтказа {
        _ = try СхемыКорневогоРевьюЦепочки.декодироватьПаспортРевью(
          повторВерсии)
      }.contains("повторный_ключ"))
  }

  @Test("Runtime отвергает несовпавшие дубли полей паспорта модерации")
  func дублиМодерацииДолжныТочноСовпадать() throws {
    var конверт = try объектДокумента(
      каноническийПаспортМодерации().каноническиеДанные())
    var значение = try #require(конверт["значение"] as? [String: Any])
    значение["праваяВершина"] = объект("9")
    конверт["значение"] = значение
    let данные = try JSONSerialization.data(withJSONObject: конверт, options: [.sortedKeys])

    #expect(
      кодыСтрогогоОтказа {
        _ = try СхемыКорневогоРевьюЦепочки.декодироватьПаспортМодерации(данные)
      } == ["дубли_полей_модерации_не_совпадают"])
  }
}


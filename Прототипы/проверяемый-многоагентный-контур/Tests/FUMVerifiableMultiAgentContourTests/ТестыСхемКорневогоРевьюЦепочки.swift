private func каноническиеДанные<Значение: Encodable>(_ значение: Значение) throws -> Data {
  let кодировщик = JSONEncoder()
  кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
  return try кодировщик.encode(значение)
}

private func объектДокумента(_ данные: Data) throws -> [String: Any] {
  try #require(JSONSerialization.jsonObject(with: данные) as? [String: Any])
}

private func изменив(
  _ данные: Data,
  поле: String,
  значение: Any
) throws -> [String: Any] {
  var документ = try объектДокумента(данные)
  документ[поле] = значение
  return документ
}

private func кодыСтрогогоОтказа(
  _ действие: () throws -> Void
) -> Set<String> {
  do {
    try действие()
    Issue.record("Строгий декодер обязан был отклонить документ.")
    return []
  } catch let ошибка as ОшибкаСтрогогоДекодированияКорневогоРевьюЦепочки {
    return Set(ошибка.нарушения.map(\.код))
  } catch {
    Issue.record("Получен неожиданный тип ошибки: \(error)")
    return []
  }
}

private func объект(_ знак: Character) -> String {
  String(repeating: знак, count: 40)
}

private func хэш(_ знак: Character) -> String {
  "sha256:" + String(repeating: знак, count: 64)
}

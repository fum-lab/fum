private func добавитьИсторическуюРазвилку(
  _ корень: inout [String: Any],
  нарушение: НарушениеИсторическихГраницДерева
) throws {
  var узлы = try массивОбъектов(корень, ["сохранённые_узлы"])
  guard узлы.indices.contains(1) else {
    throw ОшибкаТестаДереваВетвевыхФорков.неверныйПуть("сохранённые_узлы/1")
  }
  var левыйВнук = узлы[1]
  левыйВнук["идентификатор_fork"] = "fork.левый-внук"
  левыйВнук["идентификатор_родителя"] = "fork.левый"
  левыйВнук["идентификатор_репозитория"] = "репозиторий.левый-внук"
  левыйВнук["рабочая_ссылка"] = "refs/heads/левый-внук"
  левыйВнук["идентификатор_checkout"] = "checkout.левый-внук"
  левыйВнук["остаток_глубины"] = нарушение == .глубина ? 1 : 0
  левыйВнук["бюджет"] = [
    "токены": нарушение == .ресурсы ? 5_000 : 1_500,
    "секунды": 400,
    "изменённые_файлы": 4,
  ]

  var правыйВнук = левыйВнук
  правыйВнук["идентификатор_fork"] = "fork.правый-внук"
  правыйВнук["идентификатор_репозитория"] = "репозиторий.правый-внук"
  правыйВнук["рабочая_ссылка"] = "refs/heads/правый-внук"
  правыйВнук["идентификатор_checkout"] = "checkout.правый-внук"
  правыйВнук["остаток_глубины"] = 0
  правыйВнук["бюджет"] = [
    "токены": 1_500,
    "секунды": 400,
    "изменённые_файлы": 4,
  ]
  узлы.append(contentsOf: [левыйВнук, правыйВнук])
  корень["сохранённые_узлы"] = узлы

  var развилки = try массивОбъектов(корень, ["сохранённые_развилки"])
  развилки.append([
    "идентификатор_поколения": "поколение.историческое",
    "идентификатор_родителя": "fork.левый",
    "дети": ["fork.левый-внук", "fork.правый-внук"],
  ])
  корень["сохранённые_развилки"] = развилки
}

private func объект(_ корень: [String: Any], _ путь: [Any]) throws -> [String: Any] {
  guard let значение = try значение(корень, путь) as? [String: Any] else {
    throw ОшибкаТестаДереваВетвевыхФорков.неверныйПуть(String(describing: путь))
  }
  return значение
}

private func массивОбъектов(_ корень: [String: Any], _ путь: [Any]) throws -> [[String: Any]] {
  guard let значение = try значение(корень, путь) as? [[String: Any]] else {
    throw ОшибкаТестаДереваВетвевыхФорков.неверныйПуть(String(describing: путь))
  }
  return значение
}

private func строка(_ корень: [String: Any], _ путь: [Any]) throws -> String {
  guard let значение = try значение(корень, путь) as? String else {
    throw ОшибкаТестаДереваВетвевыхФорков.неверныйПуть(String(describing: путь))
  }

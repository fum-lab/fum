}

private func целое(_ корень: [String: Any], _ путь: [Any]) throws -> Int {
  guard let значение = try значение(корень, путь) as? NSNumber else {
    throw ОшибкаТестаДереваВетвевыхФорков.неверныйПуть(String(describing: путь))
  }
  return значение.intValue
}

private func значение(_ корень: [String: Any], _ путь: [Any]) throws -> Any {
  var текущее: Any = корень
  for часть in путь {
    if let ключ = часть as? String, let объект = текущее as? [String: Any],
      let следующее = объект[ключ]
    {
      текущее = следующее
    } else if let индекс = часть as? Int, let массив = текущее as? [Any],
      массив.indices.contains(индекс)
    {
      текущее = массив[индекс]
    } else {
      throw ОшибкаТестаДереваВетвевыхФорков.неверныйПуть(String(describing: путь))
    }
  }
  return текущее
}

private func установить(_ корень: inout [String: Any], _ путь: [Any], _ новое: Any) throws {
  guard let первый = путь.first as? String else {
    throw ОшибкаТестаДереваВетвевыхФорков.неверныйПуть(String(describing: путь))
  }
  if путь.count == 1 {
    корень[первый] = новое
    return
  }
  var хвост = Array(путь.dropFirst())
  var значение = корень[первый] as Any
  try установитьВЗначении(&значение, &хвост, новое, исходныйПуть: путь)
  корень[первый] = значение
}

private func установитьВЗначении(
  _ текущее: inout Any,
  _ путь: inout [Any],
  _ новое: Any,
  исходныйПуть: [Any]
) throws {
  guard let часть = путь.first else {
    текущее = новое
    return
  }
  путь.removeFirst()
  if let ключ = часть as? String, var объект = текущее as? [String: Any],
    var вложенное = объект[ключ]
  {
    try установитьВЗначении(&вложенное, &путь, новое, исходныйПуть: исходныйПуть)
    объект[ключ] = вложенное
    текущее = объект
    return
  }
  if let индекс = часть as? Int, var массив = текущее as? [Any], массив.indices.contains(индекс) {
    var вложенное = массив[индекс]
    try установитьВЗначении(&вложенное, &путь, новое, исходныйПуть: исходныйПуть)
    массив[индекс] = вложенное
    текущее = массив
    return
  }
  throw ОшибкаТестаДереваВетвевыхФорков.неверныйПуть(String(describing: исходныйПуть))
}

private func повтор(_ символ: Character, _ число: Int) -> String {
  String(repeating: String(символ), count: число)
}

private func хэш(_ текст: String) -> String {
  "sha256:" + String(repeating: текст.isEmpty ? "0" : "f", count: 64)
}

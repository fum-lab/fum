import Foundation

private let предельныйРазмерСхемыКорневогоРевьюЦепочки = 1_048_576

public enum ОшибкаСхемКорневогоРевьюЦепочки: Error, Sendable {
  case ресурсОтсутствует(String)
  case ресурсСлишкомВелик(String, Int)
}

public struct ОшибкаСтрогогоДекодированияКорневогоРевьюЦепочки:
  Error, Equatable, Sendable
{
  public let нарушения: [НарушениеЗакрытойСхемы]

  public init(нарушения: [НарушениеЗакрытойСхемы]) {
    self.нарушения = нарушения
  }
}

public enum СхемыКорневогоРевьюЦепочки {
  public static func загрузитьПаспортРевью() throws -> Data {
    try загрузить("схема-паспорта-корневого-ревью-цепочки-v1")
  }

  public static func загрузитьПаспортМодерации() throws -> Data {
    try загрузить("схема-паспорта-модерации-корневой-цепочки-v1")
  }

  public static func загрузитьКонвертЗапросаСлияния() throws -> Data {
    try загрузить("схема-конверта-запроса-слияния-цепочки-v1")
  }

  public static func декодироватьПаспортРевью(
    _ данные: Data
  ) throws -> ПаспортКорневогоРевьюЦепочки {
    try декодировать(
      данные,
      идентичностьСхемы: "fum.паспорт-корневого-ревью-цепочки",
      схема: загрузитьПаспортРевью()
    )
  }

  public static func декодироватьПаспортМодерации(
    _ данные: Data
  ) throws -> ПаспортМодерацииКорневойЦепочки {
    let паспорт: ПаспортМодерацииКорневойЦепочки = try декодировать(
      данные,
      идентичностьСхемы: "fum.паспорт-модерации-корневой-цепочки",
      схема: загрузитьПаспортМодерации()
    )
    guard
      паспорт.идентификаторЛевогоРебёнка
        == паспорт.левыйРезультат.идентификаторФорка,
      паспорт.идентификаторЛевогоРепозитория
        == паспорт.левыйРезультат.идентификаторРепозитория,
      паспорт.леваяБаза == паспорт.левыйРезультат.исходнаяВершина,
      паспорт.леваяРабочаяСсылка == паспорт.левыйРезультат.рабочаяСсылка,
      паспорт.леваяСсылкаРезультата == паспорт.левыйРезультат.ссылкаРезультата,
      паспорт.леваяВершина == паспорт.левыйРезультат.вершинаРезультата,
      паспорт.идентификаторПравогоРебёнка
        == паспорт.правыйРезультат?.идентификаторФорка,
      паспорт.идентификаторПравогоРепозитория
        == паспорт.правыйРезультат?.идентификаторРепозитория,
      паспорт.праваяБаза == паспорт.правыйРезультат?.исходнаяВершина,
      паспорт.праваяРабочаяСсылка == паспорт.правыйРезультат?.рабочаяСсылка,
      паспорт.праваяСсылкаРезультата == паспорт.правыйРезультат?.ссылкаРезультата,
      паспорт.праваяВершина == паспорт.правыйРезультат?.вершинаРезультата
    else {
      throw ОшибкаСтрогогоДекодированияКорневогоРевьюЦепочки(
        нарушения: [
          НарушениеЗакрытойСхемы(
            код: "дубли_полей_модерации_не_совпадают",
            путь: "/значение",
            сообщение: "Дубли полей должны точно совпадать с замороженными результатами."
          )
        ]
      )
    }
    return паспорт
  }

  public static func декодироватьКонвертЗапросаСлияния(
    _ данные: Data
  ) throws -> КонвертЗапросаСлиянияЦепочки {
    try декодировать(
      данные,
      идентичностьСхемы: "fum.конверт-запроса-слияния-цепочки",
      схема: загрузитьКонвертЗапросаСлияния()
    )
  }

  private static func декодировать<Значение: Decodable>(
    _ данные: Data,
    идентичностьСхемы: String,
    схема: Data
  ) throws -> Значение {
    var обнаружитель = JSONDuplicateKeyDetector(data: данные)
    do {
      let повторы = try обнаружитель.scan()
      guard повторы.isEmpty else {
        throw ошибка(
          повторы.map {
            НарушениеЗакрытойСхемы(
              код: "повторный_ключ",
              путь: $0,
              сообщение: "Канонический JSON содержит повторный ключ."
            )
          }
        )
      }
    } catch let ошибка as ОшибкаСтрогогоДекодированияКорневогоРевьюЦепочки {
      throw ошибка
    } catch JSONScanError.structureLimitExceeded {
      throw ошибка([
        НарушениеЗакрытойСхемы(
          код: "предел_структуры_документа",
          путь: "",
          сообщение: "Канонический JSON превышает предел структуры."
        )
      ])
    } catch {
      throw ошибка([
        НарушениеЗакрытойСхемы(
          код: "неверный_json",
          путь: "",
          сообщение: "Ожидался завершённый канонический JSON-объект."
        )
      ])
    }
    guard данные.count <= предельныйРазмерСхемыКорневогоРевьюЦепочки,
      let корень = try? JSONSerialization.jsonObject(with: данные) as? [String: Any]
    else {
      throw ошибка([
        НарушениеЗакрытойСхемы(
          код: "неверный_json",
          путь: "",
          сообщение: "Ожидался завершённый канонический JSON-объект."
        )
      ])
    }
    if let путь = путьПервойНенормализованнойСтроки(корень) {
      throw ошибка([
        НарушениеЗакрытойСхемы(
          код: "строка_не_NFC",
          путь: путь,
          сообщение: "Ключи и строки должны быть нормализованы в NFC."
        )
      ])
    }
    let разрешённыеКлючи: Set<String> = [
      "идентичностьСхемы", "версияСхемы", "значение",
    ]
    guard Set(корень.keys) == разрешённыеКлючи else {
      let неизвестные = Set(корень.keys).subtracting(разрешённыеКлючи).sorted()
      let отсутствующие = разрешённыеКлючи.subtracting(корень.keys).sorted()
      let нарушения =
        неизвестные.map {
          НарушениеЗакрытойСхемы(
            код: "неизвестное_поле",
            путь: "/\($0)",
            сообщение: "Поле не входит в закрытый канонический конверт."
          )
        }
        + отсутствующие.map {
          НарушениеЗакрытойСхемы(
            код: "обязательное_поле_отсутствует",
            путь: "/\($0)",
            сообщение: "Обязательное поле канонического конверта отсутствует."
          )
        }
      throw ошибка(нарушения)
    }
    guard корень["идентичностьСхемы"] as? String == идентичностьСхемы else {
      throw ошибка([
        НарушениеЗакрытойСхемы(
          код: "неверная_идентичность_схемы",
          путь: "/идентичностьСхемы",
          сообщение: "Идентичность схемы не совпадает с ожидаемой."
        )
      ])
    }
    guard (корень["версияСхемы"] as? NSNumber)?.intValue == 1,
      let значение = корень["значение"],
      JSONSerialization.isValidJSONObject(значение),
      let данныеЗначения = try? JSONSerialization.data(
        withJSONObject: значение,
        options: [.sortedKeys]
      )
    else {
      throw ошибка([
        НарушениеЗакрытойСхемы(
          код: "неверная_версия_схемы",
          путь: "/версияСхемы",
          сообщение: "Поддерживается только версия 1."
        )
      ])
    }
    let нарушения = ПроверкаЗакрытойСхемы.проверитьДокумент(
      данныеЗначения,
      по: схема
    )
    guard нарушения.isEmpty else { throw ошибка(нарушения) }
    do {
      return try JSONDecoder().decode(Значение.self, from: данныеЗначения)
    } catch {
      throw ошибка([
        НарушениеЗакрытойСхемы(
          код: "несовпадение_runtime_и_схемы",
          путь: "/значение",
          сообщение: "Типизированное декодирование не совпало с закрытой схемой."
        )
      ])
    }
  }

  private static func ошибка(
    _ нарушения: [НарушениеЗакрытойСхемы]
  ) -> ОшибкаСтрогогоДекодированияКорневогоРевьюЦепочки {
    ОшибкаСтрогогоДекодированияКорневогоРевьюЦепочки(
      нарушения: нарушения.sorted {
        if $0.код != $1.код { return $0.код < $1.код }
        return $0.путь < $1.путь
      }
    )
  }

  private static func загрузить(_ имя: String) throws -> Data {
    let прямойАдрес = Bundle.module.resourceURL?
      .appendingPathComponent("Фикстуры", isDirectory: true)
      .appendingPathComponent("КорневоеРевьюЦепочки", isDirectory: true)
      .appendingPathComponent(имя)
      .appendingPathExtension("json")
    let адрес =
      (прямойАдрес.flatMap {
        FileManager.default.fileExists(atPath: $0.path) ? $0 : nil
      })
      ?? Bundle.module.url(
        forResource: имя,
        withExtension: "json",
        subdirectory: "Фикстуры/КорневоеРевьюЦепочки"
      )
      ?? Bundle.module.url(
        forResource: имя,
        withExtension: "json",
        subdirectory: "КорневоеРевьюЦепочки"
      )
      ?? Bundle.module.url(forResource: имя, withExtension: "json")
    guard let адрес else {
      throw ОшибкаСхемКорневогоРевьюЦепочки.ресурсОтсутствует(имя)
    }
    let значения = try адрес.resourceValues(forKeys: [.fileSizeKey])
    guard let размер = значения.fileSize,
      размер <= предельныйРазмерСхемыКорневогоРевьюЦепочки
    else {
      throw ОшибкаСхемКорневогоРевьюЦепочки.ресурсСлишкомВелик(
        имя,
        значения.fileSize ?? -1
      )
    }
    let данные = try Data(contentsOf: адрес, options: [.mappedIfSafe])
    guard данные.count <= предельныйРазмерСхемыКорневогоРевьюЦепочки else {
      throw ОшибкаСхемКорневогоРевьюЦепочки.ресурсСлишкомВелик(имя, данные.count)
    }
    return данные
  }
}

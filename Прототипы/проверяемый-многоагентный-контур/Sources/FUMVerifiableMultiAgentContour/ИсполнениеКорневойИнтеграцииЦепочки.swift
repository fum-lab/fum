}

private func каноническиеДанныеАртефактаКорневойИнтеграции<Значение: Encodable>(
  идентичностьСхемы: String,
  значение: Значение
) throws -> Data {
  let кодировщик = JSONEncoder()
  кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
  return try кодировщик.encode(
    КонвертКаноническогоАртефактаКорневойИнтеграции(
      идентичностьСхемы: идентичностьСхемы,
      версияСхемы: 1,
      значение: значение
    )
  )
}

private func хэшАртефактаКорневойИнтеграции(_ данные: Data) -> String {
  "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}


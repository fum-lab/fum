public struct ИсполнительКорневойИнтеграцииЦепочки: Sendable {
  private let исполняемыйФайлГит: URL
  private let перехваты: ПерехватыИсполненияКорневойИнтеграцииЦепочки

  public init(
    исполняемыйФайлГит: URL,
    перехваты: ПерехватыИсполненияКорневойИнтеграцииЦепочки = .init()
  ) {
    self.исполняемыйФайлГит = исполняемыйФайлГит
    self.перехваты = перехваты
  }

  public func исполнить(
    _ запрос: ЗапросИсполненияКорневойИнтеграцииЦепочки
  ) throws -> РезультатИсполненияКорневойИнтеграцииЦепочки {
    let разрешение = запрос.разрешение
    let исходный = запрос.исходныйРепозиторий.standardizedFileURL.resolvingSymlinksInPath()
    let целевой = запрос.целевойРепозиторий.standardizedFileURL.resolvingSymlinksInPath()
    guard разрешение.действительно,
      разрешение.доступноЛинейномуИсполнителю,
      let диапазон = разрешение.диапазоны.first,
      let исходнаяСсылка = разрешение.исходнаяСсылка,
      запрос.исходныйРепозиторий.isFileURL,
      запрос.целевойРепозиторий.isFileURL,
      исходный.path == диапазон.каноническийПутьРепозитория,
      целевой.path == разрешение.каноническийПутьЦелевогоРепозитория,
      запрос.исходнаяСсылка == nil || запрос.исходнаяСсылка == исходнаяСсылка,
      try репозиторийБезРабочейКопии(исходный),
      try репозиторийБезРабочейКопии(целевой),
      допустимаяПрямаяСсылка(исходнаяСсылка, в: исходный),
      допустимаяПрямаяСсылка(разрешение.целеваяСсылка, в: целевой),
      форматОбъектаСовпадает(разрешение.новаяВершина, с: исходный),
      форматОбъектаСовпадает(разрешение.ожидаемаяВершина, с: целевой)
    else {
      return результат(.диапазонНедействителен, разрешение, наблюдаемая: nil)
    }

    let наблюдаемаяДо = try вершинаСсылки(разрешение.целеваяСсылка, в: целевой)
    guard
      (try? вершинаСсылки(исходнаяСсылка, в: исходный))
        == разрешение.новаяВершина,
      (try? линейныйДиапазон(
        в: исходный,
        база: диапазон.база,
        вершина: диапазон.вершина
      )) == диапазон.коммиты.map(\.объект)
    else {
      return результат(.диапазонНедействителен, разрешение, наблюдаемая: наблюдаемаяДо)
    }

    let ссылкаУдержания =
      "refs/fum/корневая-интеграция/" + String(разрешение.хэшРешения.dropFirst("sha256:".count))
    let передать = try гит(
      [
        "fetch", "--quiet", "--no-tags", "--force", "--",
        исходный.path, "\(исходнаяСсылка):\(ссылкаУдержания)",
      ],
      в: целевой
    )
    guard передать.код == 0,
      (try? вершинаСсылки(ссылкаУдержания, в: целевой)) == разрешение.новаяВершина,
      (try? линейныйДиапазон(
        в: целевой,
        база: диапазон.база,
        вершина: диапазон.вершина
      )) == диапазон.коммиты.map(\.объект)
    else {
      return результат(.диапазонНедействителен, разрешение, наблюдаемая: наблюдаемаяДо)
    }
    if наблюдаемаяДо == разрешение.новаяВершина {
      return результат(.ужеИнтегрировано, разрешение, наблюдаемая: наблюдаемаяДо)
    }
    guard наблюдаемаяДо == разрешение.ожидаемаяВершина else {
      return результат(.цельСдвинута, разрешение, наблюдаемая: наблюдаемаяДо)
    }

    try перехваты.передСравнениемИЗаменой?()
    let нагрузка = Data(
      ("start\noption no-deref\nupdate \(разрешение.целеваяСсылка) "
        + "\(разрешение.новаяВершина) \(разрешение.ожидаемаяВершина)\nprepare\ncommit\n")
        .utf8
    )
    let переход = try гит(["update-ref", "--stdin"], в: целевой, ввод: нагрузка)
    if переход.код == 0 {
      _ = try? перехваты.послеСравненияИЗамены?()
      let авторитетнаяВершина = try? вершинаСсылки(
        разрешение.целеваяСсылка,
        в: целевой
      )
      return результат(
        авторитетнаяВершина == разрешение.новаяВершина
          ? .интегрировано : .цельСдвинута,
        разрешение,
        наблюдаемая: авторитетнаяВершина
      )
    }
    let авторитетнаяВершина = try? вершинаСсылки(
      разрешение.целеваяСсылка,
      в: целевой
    )
    if авторитетнаяВершина == разрешение.новаяВершина {
      return результат(.ужеИнтегрировано, разрешение, наблюдаемая: авторитетнаяВершина)
    }
    return результат(.цельСдвинута, разрешение, наблюдаемая: авторитетнаяВершина)
  }

  private func результат(
    _ исход: ИсходИсполненияКорневойИнтеграцииЦепочки,
    _ разрешение: РазрешениеКорневойИнтеграцииЦепочки,
    наблюдаемая: String?
  ) -> РезультатИсполненияКорневойИнтеграцииЦепочки {
    РезультатИсполненияКорневойИнтеграцииЦепочки(
      исход: исход,
      ожидаемаяВершина: разрешение.ожидаемаяВершина,
      наблюдаемаяВершина: наблюдаемая,
      новаяВершина: разрешение.новаяВершина,
      кандидатыСохранены: true
    )
  }

  private func репозиторийБезРабочейКопии(_ адрес: URL) throws -> Bool {
    let ответ = try гит(["rev-parse", "--is-bare-repository"], в: адрес)
    return ответ.код == 0 && текст(ответ.данные) == "true"
  }

  private func допустимаяПрямаяСсылка(_ ссылка: String, в репозиторий: URL) -> Bool {
    guard ссылка.hasPrefix("refs/"),
      (try? гит(["check-ref-format", ссылка], в: репозиторий).код) == 0
    else { return false }
    return (try? гит(["symbolic-ref", "-q", ссылка], в: репозиторий).код) == 1
  }

  private func форматОбъектаСовпадает(_ объект: String, с репозиторий: URL) -> Bool {
    guard let ответ = try? гит(["rev-parse", "--show-object-format"], в: репозиторий),
      ответ.код == 0
    else { return false }
    let формат = текст(ответ.данные)
    return (формат == "sha1" && объект.count == 40)
      || (формат == "sha256" && объект.count == 64)
  }

  private func вершинаСсылки(_ ссылка: String, в репозиторий: URL) throws -> String {
    let ответ = try гит(["rev-parse", "--verify", "\(ссылка)^{commit}"], в: репозиторий)
    guard ответ.код == 0 else { throw ОшибкаИсполненияКорневойИнтеграцииЦепочки.гит }
    return текст(ответ.данные)
  }

  private func линейныйДиапазон(
    в репозиторий: URL,
    база: String,
    вершина: String
  ) throws -> [String] {
    let ответ = try гит(["rev-list", "--reverse", "\(база)..\(вершина)"], в: репозиторий)
    guard ответ.код == 0 else { throw ОшибкаИсполненияКорневойИнтеграцииЦепочки.гит }
    let объекты = текст(ответ.данные).split(separator: "\n").map(String.init)
    var предыдущая = база
    for объект in объекты {
      let родословная = try гит(
        ["rev-list", "--parents", "-n", "1", объект],
        в: репозиторий
      )
      let поля = текст(родословная.данные).split(separator: " ").map(String.init)
      guard родословная.код == 0, поля == [объект, предыдущая] else {
        throw ОшибкаИсполненияКорневойИнтеграцииЦепочки.диапазон
      }
      предыдущая = объект
    }
    guard !объекты.isEmpty, предыдущая == вершина else {
      throw ОшибкаИсполненияКорневойИнтеграцииЦепочки.диапазон
    }
    return объекты
  }

  private func гит(
    _ аргументы: [String],
    в каталог: URL,
    ввод: Data? = nil
  ) throws -> ОтветГитКорневойИнтеграции {
    let процесс = Process()
    процесс.executableURL = исполняемыйФайлГит
    процесс.arguments =
      [
        "--no-replace-objects", "--no-optional-locks",
        "-c", "core.hooksPath=\(WritingSubnodeSystemRuntime.nullDevicePath)", "-c",
        "protocol.allow=never",
        "-c", "protocol.file.allow=always",
      ] + аргументы
    процесс.currentDirectoryURL = каталог
    процесс.environment = [
      "GIT_CONFIG_NOSYSTEM": "1",
      "GIT_CONFIG_GLOBAL": WritingSubnodeSystemRuntime.nullDevicePath,
      "GIT_OPTIONAL_LOCKS": "0", "GIT_TERMINAL_PROMPT": "0", "LC_ALL": "C",
      "PATH": ProcessInfo.processInfo.environment["PATH"]
        ?? WritingSubnodeSystemRuntime.gitExecutableURL.deletingLastPathComponent().path,
    ]
    let вывод = Pipe()
    процесс.standardOutput = вывод
    процесс.standardError = вывод
    let вход: Pipe?
    if ввод != nil {
      let канал = Pipe()
      вход = канал
      процесс.standardInput = канал
    } else {
      вход = nil
    }
    try процесс.run()
    try вывод.fileHandleForWriting.close()
    if let ввод, let вход {
      try вход.fileHandleForWriting.write(contentsOf: ввод)
      try вход.fileHandleForWriting.close()
    }
    let данные = вывод.fileHandleForReading.readDataToEndOfFile()
    процесс.waitUntilExit()
    return ОтветГитКорневойИнтеграции(код: процесс.terminationStatus, данные: данные)
  }

  private func текст(_ данные: Data) -> String {
    String(decoding: данные, as: UTF8.self)
      .trimmingCharacters(in: .whitespacesAndNewlines)
  }
}

private enum ОшибкаИсполненияКорневойИнтеграцииЦепочки: Error {
  case гит
  case диапазон
}

private struct ОтветГитКорневойИнтеграции {
  let код: Int32
  let данные: Data
}

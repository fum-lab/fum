import CoreFoundation
import Foundation

private let разделительУказателяЗакрытойСхемы = "/"

public struct НарушениеЗакрытойСхемы: Equatable, Hashable, Sendable {
  public let код: String
  public let путь: String
  public let сообщение: String

  public init(код: String, путь: String, сообщение: String) {
    self.код = код
    self.путь = путь
    self.сообщение = сообщение
  }
}

/// Автономный интерпретатор конечного профиля JSON Schema Draft 2020-12,
/// используемого паспортами цепочки. Он проверяет и сами схемы, и экземпляры,
/// поэтому исполняемый валидатор не расходится с опубликованными ресурсами.
public enum ПроверкаЗакрытойСхемы {
  private static let предельныйРазмер = 1_048_576
  private static let поколение = "https://json-schema.org/draft/2020-12/schema"
  private static let поддержанныеКлючи: Set<String> = [
    "$schema", "$id", "$defs", "$ref", "title", "type", "additionalProperties",
    "required", "properties", "const", "enum", "oneOf", "anyOf", "allOf", "not",
    "if", "then", "else", "minItems", "maxItems", "uniqueItems", "items",
    "minLength", "maxLength", "pattern", "minimum", "maximum",
  ]
  private static let поддержанныеТипы: Set<String> = [
    "object", "array", "string", "integer", "number", "boolean", "null",
  ]

  public static func проверитьСхему(_ данные: Data) -> [НарушениеЗакрытойСхемы] {
    guard !данные.isEmpty, данные.count <= предельныйРазмер else {
      return [нарушение("неверная_схема", "", "Схема отсутствует или превышает предел входа.")]
    }
    var обнаружитель = JSONDuplicateKeyDetector(data: данные)
    do {
      let пути = try обнаружитель.scan()
      if !пути.isEmpty {
        return упорядочить(
          пути.map {
            нарушение("повторный_ключ", $0, "JSON-схема содержит повторный ключ.")
          }
        )
      }
    } catch JSONScanError.structureLimitExceeded {
      return [
        нарушение("предел_структуры_схемы", "", "Схема превышает предел глубины или числа узлов.")
      ]
    } catch {
      return [нарушение("неверная_схема", "", "Схема должна быть завершённым JSON-объектом.")]
    }
    guard let корень = разобратьОбъект(данные) else {
      return [нарушение("неверная_схема", "", "Схема должна быть завершённым JSON-объектом.")]
    }
    if let путь = путьПервойНенормализованнойСтроки(корень) {
      return [
        нарушение("строка_не_NFC", путь, "Ключи и строки схемы должны быть нормализованы в NFC.")
      ]
    }
    var нарушения: [НарушениеЗакрытойСхемы] = []
    if строка(корень["$schema"]) != поколение {
      нарушения.append(
        нарушение(
          "неподдерживаемое_поколение_схемы",
          "/$schema",
          "Поддерживается только локальный профиль JSON Schema Draft 2020-12."
        )
      )
    }
    проверитьУзелСхемы(
      корень,
      корень: корень,
      путь: "",
      глубина: 0,
      нарушения: &нарушения
    )
    return упорядочить(нарушения)
  }

  public static func проверитьДокумент(
    _ документ: Any,
    по данныеСхемы: Data
  ) -> [НарушениеЗакрытойСхемы] {
    let нарушенияСхемы = проверитьСхему(данныеСхемы)
    guard нарушенияСхемы.isEmpty else { return нарушенияСхемы }
    guard let корень = разобратьОбъект(данныеСхемы) else {
      return [нарушение("неверная_схема", "", "Схема должна быть завершённым JSON-объектом.")]
    }
    var нарушения: [НарушениеЗакрытойСхемы] = []
    проверитьЗначение(
      документ,
      схема: корень,
      корень: корень,
      путь: "",
      глубина: 0,
      нарушения: &нарушения
    )
    return упорядочить(нарушения)
  }

  private static func проверитьУзелСхемы(
    _ схема: [String: Any],
    корень: [String: Any],
    путь: String,
    глубина: Int,
    нарушения: inout [НарушениеЗакрытойСхемы]
  ) {
    guard глубина <= 128 else {
      нарушения.append(
        нарушение("слишком_глубокая_схема", путь, "Схема превышает предел вложенности."))
      return
    }
    for ключ in схема.keys where !поддержанныеКлючи.contains(ключ) {
      нарушения.append(
        нарушение(
          "неподдерживаемый_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + ключ,
          "Ключ не входит в автономный профиль схемы.")
      )
    }

    if let ссылка = схема["$ref"] {
      guard let ссылка = строка(ссылка), разрешить(ссылка, в: корень) != nil else {
        нарушения.append(
          нарушение(
            "неразрешимая_ссылка_схемы", путь + разделительУказателяЗакрытойСхемы + "$ref",
            "Разрешены только существующие локальные ссылки схемы."))
        return
      }
    }
    if let тип = схема["type"] {
      guard let тип = строка(тип), поддержанныеТипы.contains(тип) else {
        нарушения.append(
          нарушение(
            "неподдерживаемый_тип_схемы", путь + разделительУказателяЗакрытойСхемы + "type",
            "Тип схемы не поддержан."))
        return
      }
      if тип == "object" && схема["additionalProperties"] as? Bool != false {
        нарушения.append(
          нарушение(
            "открытый_объект_схемы",
            путь + разделительУказателяЗакрытойСхемы + "additionalProperties",
            "Каждый объект контракта должен быть закрыт.")
        )
      }
    }
    if let дополнительные = схема["additionalProperties"], дополнительные as? Bool == nil {
      нарушения.append(
        нарушение(
          "неверный_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + "additionalProperties",
          "Ожидалось логическое значение."))
    }
    if let обязательные = схема["required"] {
      guard let обязательные = обязательные as? [Any],
        обязательные.allSatisfy({ строка($0) != nil }),
        Set(обязательные.compactMap(строка)).count == обязательные.count
      else {
        нарушения.append(
          нарушение(
            "неверный_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + "required",
            "Required должен быть уникальным массивом строк."))
        return
      }
    }
    for ключ in ["minItems", "maxItems", "minLength", "maxLength"] {
      if let значение = схема[ключ], let число = точноеЦелое(значение), число >= 0 {
        continue
      } else if схема[ключ] != nil {
        нарушения.append(
          нарушение(
            "неверный_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + ключ,
            "Ожидалось неотрицательное целое число."))
      }
    }
    for ключ in ["minimum", "maximum"] where схема[ключ] != nil {
      if конечноеЧисло(схема[ключ]) == nil {
        нарушения.append(
          нарушение(
            "неверный_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + ключ,
            "Ожидалось конечное число."))
      }
    }
    if let уникальность = схема["uniqueItems"], уникальность as? Bool == nil {
      нарушения.append(
        нарушение(
          "неверный_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + "uniqueItems",
          "Ожидалось логическое значение."))
    }
    if let шаблон = схема["pattern"] {
      guard let шаблон = строка(шаблон),
        (try? NSRegularExpression(pattern: шаблон)) != nil
      else {
        нарушения.append(
          нарушение(
            "неверный_шаблон_схемы", путь + разделительУказателяЗакрытойСхемы + "pattern",
            "Регулярное выражение схемы не компилируется."))
        return
      }
    }

    for ключ in ["properties", "$defs"] where схема[ключ] != nil {
      guard let вложенные = схема[ключ] as? [String: Any] else {
        нарушения.append(
          нарушение(
            "неверный_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + ключ,
            "Ожидался объект вложенных схем."))
        continue
      }
      for (имя, значение) in вложенные {
        guard let вложенная = значение as? [String: Any] else {
          нарушения.append(
            нарушение(
              "неверный_узел_схемы", путь + разделительУказателяЗакрытойСхемы + ключ + "/" + имя,
              "Вложенная схема должна быть объектом."))
          continue
        }
        проверитьУзелСхемы(
          вложенная,
          корень: корень,
          путь: путь + разделительУказателяЗакрытойСхемы + ключ + "/" + имя,
          глубина: глубина + 1,
          нарушения: &нарушения
        )
      }
    }
    for ключ in ["oneOf", "anyOf", "allOf"] where схема[ключ] != nil {
      guard let вложенные = схема[ключ] as? [[String: Any]], !вложенные.isEmpty else {
        нарушения.append(
          нарушение(
            "неверный_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + ключ,
            "Ожидался непустой массив схем."))
        continue
      }
      for (индекс, вложенная) in вложенные.enumerated() {
        проверитьУзелСхемы(
          вложенная,
          корень: корень,
          путь: путь + разделительУказателяЗакрытойСхемы + ключ + "/\(индекс)",
          глубина: глубина + 1,
          нарушения: &нарушения
        )
      }
    }
    for ключ in ["not", "if", "then", "else", "items"] where схема[ключ] != nil {
      guard let вложенная = схема[ключ] as? [String: Any] else {
        нарушения.append(
          нарушение(
            "неверный_ключ_схемы", путь + разделительУказателяЗакрытойСхемы + ключ,
            "Ожидалась вложенная схема."))
        continue
      }
      проверитьУзелСхемы(
        вложенная,
        корень: корень,
        путь: путь + разделительУказателяЗакрытойСхемы + ключ,
        глубина: глубина + 1,
        нарушения: &нарушения
      )
    }
  }

  private static func проверитьЗначение(
    _ значение: Any,
    схема: [String: Any],
    корень: [String: Any],
    путь: String,
    глубина: Int,
    нарушения: inout [НарушениеЗакрытойСхемы]
  ) {
    guard глубина <= 256 else {
      нарушения.append(
        нарушение("слишком_глубокий_документ", путь, "Документ превышает предел вложенности."))
      return
    }
    if let ссылка = строка(схема["$ref"]), let разрешённая = разрешить(ссылка, в: корень) {
      проверитьЗначение(
        значение,
        схема: разрешённая,
        корень: корень,
        путь: путь,
        глубина: глубина + 1,
        нарушения: &нарушения
      )
    }

    if let тип = строка(схема["type"]), !соответствуетТипу(значение, тип: тип) {
      нарушения.append(нарушение("неверный_тип", путь, "Значение не соответствует типу \(тип)."))
      return
    }
    if let ожидаемое = схема["const"], !равны(значение, ожидаемое) {
      нарушения.append(
        нарушение("неверная_константа", путь, "Значение не совпадает с const схемы."))
    }
    if let варианты = схема["enum"] as? [Any],
      !варианты.contains(where: { равны(значение, $0) })
    {
      нарушения.append(
        нарушение("значение_вне_перечня", путь, "Значение не входит в закрытый перечень схемы."))
    }

    if let все = схема["allOf"] as? [[String: Any]] {
      for вложенная in все {
        проверитьЗначение(
          значение,
          схема: вложенная,
          корень: корень,
          путь: путь,
          глубина: глубина + 1,
          нарушения: &нарушения
        )
      }
    }
    if let варианты = схема["anyOf"] as? [[String: Any]],
      !варианты.contains(where: {
        подходит(значение, схема: $0, корень: корень, глубина: глубина + 1)
      })
    {
      нарушения.append(нарушение("не_выполнен_anyOf", путь, "Ни одна ветвь anyOf не выполнена."))
    }
    if let варианты = схема["oneOf"] as? [[String: Any]] {
      let число = варианты.filter {
        подходит(значение, схема: $0, корень: корень, глубина: глубина + 1)
      }.count
      if число != 1 {
        нарушения.append(
          нарушение(
            "не_выполнен_oneOf", путь,
            "Должна выполняться ровно одна ветвь oneOf, выполнено: \(число)."))
      }
    }
    if let запрет = схема["not"] as? [String: Any],
      подходит(значение, схема: запрет, корень: корень, глубина: глубина + 1)
    {
      нарушения.append(
        нарушение("выполнена_запрещённая_схема", путь, "Значение совпало с ветвью not."))
    }
    if let условие = схема["if"] as? [String: Any] {
      let выполнено = подходит(
        значение,
        схема: условие,
        корень: корень,
        глубина: глубина + 1
      )
      let ключ = выполнено ? "then" : "else"
      if let следствие = схема[ключ] as? [String: Any] {
        проверитьЗначение(
          значение,
          схема: следствие,
          корень: корень,
          путь: путь,
          глубина: глубина + 1,
          нарушения: &нарушения
        )
      }
    }

    if let объект = значение as? [String: Any] {
      let свойства = схема["properties"] as? [String: Any] ?? [:]
      if let обязательные = схема["required"] as? [String] {
        for ключ in обязательные where объект[ключ] == nil {
          нарушения.append(
            нарушение(
              "обязательное_поле_отсутствует", путь + разделительУказателяЗакрытойСхемы + ключ,
              "Обязательное поле отсутствует."))
        }
      }
      if схема["additionalProperties"] as? Bool == false {
        for ключ in объект.keys where свойства[ключ] == nil {
          нарушения.append(
            нарушение(
              "неизвестное_поле", путь + разделительУказателяЗакрытойСхемы + ключ,
              "Закрытый объект содержит неизвестное поле."))
        }
      }
      for (ключ, вложенная) in свойства {
        guard let подчинённое = объект[ключ], let вложенная = вложенная as? [String: Any] else {
          continue
        }
        проверитьЗначение(
          подчинённое,
          схема: вложенная,
          корень: корень,
          путь: путь + разделительУказателяЗакрытойСхемы + ключ,
          глубина: глубина + 1,
          нарушения: &нарушения
        )
      }
    }

    if let массив = значение as? [Any] {
      if let минимум = точноеЦелое(схема["minItems"]), массив.count < минимум {
        нарушения.append(нарушение("слишком_мало_элементов", путь, "Массив короче minItems."))
      }
      if let максимум = точноеЦелое(схема["maxItems"]), массив.count > максимум {
        нарушения.append(нарушение("слишком_много_элементов", путь, "Массив длиннее maxItems."))
      }
      if схема["uniqueItems"] as? Bool == true {
        var ключи: Set<String> = []
        for элемент in массив {
          guard let ключ = каноническийКлюч(элемент), ключи.insert(ключ).inserted else {
            нарушения.append(
              нарушение("повторный_элемент", путь, "Массив с uniqueItems содержит повтор."))
            break
          }
        }
      }
      if let вложенная = схема["items"] as? [String: Any] {
        for (индекс, элемент) in массив.enumerated() {
          проверитьЗначение(
            элемент,
            схема: вложенная,
            корень: корень,
            путь: путь + разделительУказателяЗакрытойСхемы + "\(индекс)",
            глубина: глубина + 1,
            нарушения: &нарушения
          )
        }
      }
    }

    if let строковое = значение as? String {
      let длина = строковое.unicodeScalars.count
      if let минимум = точноеЦелое(схема["minLength"]), длина < минимум {
        нарушения.append(нарушение("слишком_короткая_строка", путь, "Строка короче minLength."))
      }
      if let максимум = точноеЦелое(схема["maxLength"]), длина > максимум {
        нарушения.append(нарушение("слишком_длинная_строка", путь, "Строка длиннее maxLength."))
      }
      if let шаблон = строка(схема["pattern"]),
        let выражение = try? NSRegularExpression(pattern: шаблон),
        выражение.firstMatch(
          in: строковое,
          range: NSRange(строковое.startIndex..., in: строковое)
        ) == nil
      {
        нарушения.append(
          нарушение(
            "строка_не_совпадает_с_шаблоном", путь, "Строка не соответствует pattern схемы."))
      }
    }

    if let число = конечноеЧисло(значение) {
      if let минимум = конечноеЧисло(схема["minimum"]), число < минимум {
        нарушения.append(нарушение("число_меньше_минимума", путь, "Число меньше minimum."))
      }
      if let максимум = конечноеЧисло(схема["maximum"]), число > максимум {
        нарушения.append(нарушение("число_больше_максимума", путь, "Число больше maximum."))
      }
    }
  }

  private static func подходит(
    _ значение: Any,
    схема: [String: Any],
    корень: [String: Any],
    глубина: Int
  ) -> Bool {
    var нарушения: [НарушениеЗакрытойСхемы] = []
    проверитьЗначение(
      значение,
      схема: схема,
      корень: корень,
      путь: "",
      глубина: глубина,
      нарушения: &нарушения
    )
    return нарушения.isEmpty
  }

  private static func разрешить(
    _ ссылка: String,
    в корневаяСхема: [String: Any]
  ) -> [String: Any]? {
    guard ссылка.hasPrefix("#/"),
      let декодированная = String(ссылка.dropFirst(2)).removingPercentEncoding
    else { return nil }
    var текущее: Any = корневаяСхема
    for сыройКомпонент in декодированная.split(separator: "/", omittingEmptySubsequences: false) {
      let компонент = сыройКомпонент.replacingOccurrences(of: "~1", with: "/")
        .replacingOccurrences(of: "~0", with: "~")
      guard let объект = текущее as? [String: Any], let следующее = объект[компонент] else {
        return nil
      }
      текущее = следующее
    }
    return текущее as? [String: Any]
  }

  private static func соответствуетТипу(_ значение: Any, тип: String) -> Bool {
    switch тип {
    case "object":
      return значение is [String: Any]
    case "array":
      return значение is [Any]
    case "string":
      return значение is String
    case "integer":
      return точноеЦелое(значение) != nil
    case "number":
      return конечноеЧисло(значение) != nil
    case "boolean":
      return являетсяЛогическим(значение)
    case "null":
      return значение is NSNull
    default:
      return false
    }
  }

  private static func являетсяЛогическим(_ значение: Any?) -> Bool {
    guard let число = значение as? NSNumber else { return false }
    return CFGetTypeID(число) == CFBooleanGetTypeID()
  }

  private static func точноеЦелое(_ значение: Any?) -> Int? {
    guard let число = значение as? NSNumber, !являетсяЛогическим(число) else {
      return nil
    }
    return Int(число.stringValue)
  }

  private static func конечноеЧисло(_ значение: Any?) -> Double? {
    guard let число = значение as? NSNumber, !являетсяЛогическим(число),
      число.doubleValue.isFinite
    else { return nil }
    return число.doubleValue
  }

  private static func равны(_ левое: Any, _ правое: Any) -> Bool {
    guard let левыйКлюч = каноническийКлюч(левое),
      let правыйКлюч = каноническийКлюч(правое)
    else { return false }
    return левыйКлюч == правыйКлюч
  }

  private static func каноническийКлюч(_ значение: Any) -> String? {
    guard JSONSerialization.isValidJSONObject([значение]),
      let данные = try? JSONSerialization.data(
        withJSONObject: [значение],
        options: [.sortedKeys, .withoutEscapingSlashes]
      )
    else { return nil }
    return данные.base64EncodedString()
  }

  private static func разобратьОбъект(_ данные: Data) -> [String: Any]? {
    guard let значение = try? JSONSerialization.jsonObject(with: данные),
      let объект = значение as? [String: Any]
    else { return nil }
    return объект
  }

  private static func строка(_ значение: Any?) -> String? {
    значение as? String
  }

  private static func нарушение(
    _ код: String,
    _ путь: String,
    _ сообщение: String
  ) -> НарушениеЗакрытойСхемы {
    НарушениеЗакрытойСхемы(код: код, путь: путь, сообщение: сообщение)
  }

  private static func упорядочить(
    _ нарушения: [НарушениеЗакрытойСхемы]
  ) -> [НарушениеЗакрытойСхемы] {
    Array(Set(нарушения)).sorted {
      if $0.код != $1.код { return $0.код < $1.код }
      if $0.путь != $1.путь { return $0.путь < $1.путь }
      return $0.сообщение < $1.сообщение
    }
  }
}

func путьПервойНенормализованнойСтроки(
  _ значение: Any,
  путь: String = ""
) -> String? {
  if let строка = значение as? String {
    return нормализованаКанонически(строка) ? nil : путь
  }
  if let массив = значение as? [Any] {
    for (индекс, элемент) in массив.enumerated() {
      if let найденный = путьПервойНенормализованнойСтроки(
        элемент,
        путь: путь + разделительУказателяЗакрытойСхемы + "\(индекс)"
      ) {
        return найденный
      }
    }
    return nil
  }
  if let объект = значение as? [String: Any] {
    for ключ in объект.keys.sorted() {
      let часть = ключ.replacingOccurrences(of: "~", with: "~0")
        .replacingOccurrences(of: "/", with: "~1")
      let путьКлюча = путь + разделительУказателяЗакрытойСхемы + часть
      if !нормализованаКанонически(ключ) {
        return путьКлюча
      }
      if let вложенный = объект[ключ],
        let найденный = путьПервойНенормализованнойСтроки(
          вложенный,
          путь: путьКлюча
        )
      {
        return найденный
      }
    }
  }
  return nil
}

private func нормализованаКанонически(_ строка: String) -> Bool {
  строка.utf8.elementsEqual(
    строка.precomposedStringWithCanonicalMapping.utf8
  )
}

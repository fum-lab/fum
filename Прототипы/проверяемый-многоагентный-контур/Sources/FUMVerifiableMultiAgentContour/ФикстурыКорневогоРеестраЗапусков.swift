          else {
            throw ОшибкаКорневогоРеестраЗапусков(
              "фикстура_не_собрала_активированную_ветвь"
            )
          }
          let материализованная = МатериализованнаяВетвьКорневойФикстуры(
            поколение: спецификация.идентификатор,
            исходнаяВершина: спецификация.исходнаяВершина,

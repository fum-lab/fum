private struct КонтекстФикстурыКорневогоРеестра {
  let корень: URL
  let адресРеестра: URL
  let левыйИсточник: URL
  let правыйИсточник: URL
  let вершина: String

  init(корень: URL) throws {
    self.корень = корень
    self.адресРеестра = корень.appendingPathComponent("реестр", isDirectory: true)
    self.левыйИсточник = корень.appendingPathComponent("левый.git", isDirectory: true)
    self.правыйИсточник = корень.appendingPathComponent("правый.git", isDirectory: true)
    try FileManager.default.createDirectory(at: корень, withIntermediateDirectories: true)
    let исходник = корень.appendingPathComponent("исходник", isDirectory: true)
    _ = try гитФикстуры(["init", "--initial-branch=main", исходник.path], корень: корень)
    _ = try гитФикстуры(["config", "user.name", "FUM Fixture"], корень: исходник)
    _ = try гитФикстуры(["config", "user.email", "fixture@fum.invalid"], корень: исходник)
    try Data("база\n".utf8).write(to: исходник.appendingPathComponent("база.txt"), options: .atomic)
    _ = try гитФикстуры(["add", "--all"], корень: исходник)
    _ = try гитФикстуры(["commit", "-m", "база"], корень: исходник)
    self.вершина = try гитФикстуры(["rev-parse", "HEAD"], корень: исходник)
    _ = try гитФикстуры(["clone", "--bare", исходник.path, левыйИсточник.path], корень: корень)
    _ = try гитФикстуры(["clone", "--bare", исходник.path, правыйИсточник.path], корень: корень)
  }

  func подготовитьРеестр(
    идентичность: ИдентичностьКонтроллераЗадач = .недоступна,
    общийИсточник: Bool = false,
    ресурсныеПолномочия: [СторонаВетвевогоФорка: [КорневыеПолномочияРесурсногоНазначения]] = [:]
  ) throws -> КорневойРеестрЗапусков {
    let реестр = try КорневойРеестрЗапусков(каталог: адресРеестра)
    try реестр.подготовитьПоколение(
      спецификация(
        поколение: "generation.1", суффикс: "1", идентичность: идентичность,
        общийИсточник: общийИсточник,
        ресурсныеПолномочия: ресурсныеПолномочия))
    return реестр
  }

  func спецификация(
    поколение: String,
    суффикс: String,
    повторПары: Bool = false,
    повторКопии: Bool = false,
    идентичность: ИдентичностьКонтроллераЗадач = .недоступна,
    общийИсточник: Bool = false,
    повторФорка: Bool = false,
    повторПопытки: Bool = false,
    повторИсточника: Bool = false,
    повторФизическойКопии: Bool = false,
    ресурсныеПолномочия: [СторонаВетвевогоФорка: [КорневыеПолномочияРесурсногоНазначения]] = [:]
  ) -> СпецификацияПоколенияКорневогоЗапуска {
    let леваяПара =
      повторПары
      ? ("репозиторий.левый.1", "refs/heads/left-1")
      : ("репозиторий.левый.\(суффикс)", "refs/heads/left-\(суффикс)")
    let леваяКопия = повторКопии ? "checkout.left.1" : "checkout.left.\(суффикс)"
    let правыйИсточникФакт =
      повторИсточника
      ? левыйИсточник
      : (общийИсточник ? левыйИсточник : правыйИсточник)
    let левыйИсточникФакт = повторИсточника ? правыйИсточник : левыйИсточник
    let физическийПутьЛевойКопии =
      повторФизическойКопии
      ? корень.appendingPathComponent("клон-правый-1")
      : корень.appendingPathComponent("клон-левый-\(суффикс)")
    let левая = СпецификацияВетвиКорневогоЗапуска(
      сторона: .левая, идентификаторНазначения: "assignment.left.\(суффикс)", роль: "автор",
      идентификаторРебёнка: "child.left.\(суффикс)",
      идентификаторФорка: повторФорка ? "fork.left.1" : "fork.left.\(суффикс)",
      идентификаторРепозитория: леваяПара.0, рабочаяСсылка: леваяПара.1,
      идентификаторРабочейКопии: леваяКопия, адресИсточника: левыйИсточникФакт,
      адресРабочейКопии: физическийПутьЛевойКопии,
      идентификаторПопытки: повторПопытки ? "attempt.left.1" : "attempt.left.\(суффикс)",
      идентификаторШага: "step.left.\(суффикс)", идентификаторПроекта: "project.local",
      ресурсныеПолномочия: ресурсныеПолномочия[.левая] ?? [])
    let правая = СпецификацияВетвиКорневогоЗапуска(
      сторона: .правая, идентификаторНазначения: "assignment.right.\(суффикс)", роль: "критик",
      идентификаторРебёнка: "child.right.\(суффикс)", идентификаторФорка: "fork.right.\(суффикс)",
      идентификаторРепозитория: "репозиторий.правый.\(суффикс)",
      рабочаяСсылка: "refs/heads/right-\(суффикс)",
      идентификаторРабочейКопии: "checkout.right.\(суффикс)", адресИсточника: правыйИсточникФакт,
      адресРабочейКопии: корень.appendingPathComponent("клон-правый-\(суффикс)"),
      идентификаторПопытки: "attempt.right.\(суффикс)", идентификаторШага: "step.right.\(суффикс)",
      идентификаторПроекта: "project.local",
      ресурсныеПолномочия: ресурсныеПолномочия[.правая] ?? [])
    return СпецификацияПоколенияКорневогоЗапуска(
      идентификатор: поколение, исходнаяВершина: вершина, идентичностьКонтроллера: идентичность,
      идентификаторКонтроллера: идентичность == .доказана ? "desktop.singleton.1" : nil,
      ветви: [левая, правая])
  }


      var запросы: [СторонаВетвевогоФорка: ЗапросСозданияЗадачи] = [:]
      for сторона in стороныФикстурыКорневогоРеестра {
        guard let ветвь = материализованныеВетви[сторона],
          let полномочия = ресурсныеПолномочия[сторона],
          полномочия.count == 1,

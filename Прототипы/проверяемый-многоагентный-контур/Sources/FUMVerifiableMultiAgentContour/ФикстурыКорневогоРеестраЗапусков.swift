          throw ОшибкаКорневогоРеестраЗапусков(
            "фикстура_требует_одни_ресурсные_полномочия_ветви"
          )
        }
        let назначение = структурированноеРесурсноеНазначениеКорневойФикстуры(
          ветвь: ветвь,
          полномочия: полномочие
        )
        let хэшНазначения = try реестр.зарегистрироватьРесурсноеНазначение(назначение)
        let ресурснаяПопытка = "ресурсная-попытка-host-\(сторона.rawValue)"
        let допуск = try реестр.запроситьРесурсныйДопуск(
          назначение: назначение.идентификатор,
          попытка: ресурснаяПопытка,
          ожидаемыйХэшНазначения: хэшНазначения
        )
        guard допуск.состояние == .зарезервирована,
          допуск.хэшДопуска != nil
        else {
          throw ОшибкаКорневогоРеестраЗапусков(
            "фикстура_не_получила_ресурсный_допуск_до_host"
          )
        }
        try реестр.выполнитьЕдинственныйВызов(
          поколение: ветвь.поколение,
          сторона: сторона,
          среда: среда
        )
        let запрос = try среда.запрос(сторона: сторона)
        let задача = сторона == .левая ? "task.left" : "task.right"
        let средаЗадачи = сторона == .левая ? "host.left" : "host.right"
        try реестр.подтвердитьСеанс(
          поколение: ветвь.поколение,
          сторона: сторона,
          переменнаяСеанса: задача,
          билет: свидетельствоНеактивногоБилетаФикстуры(
            задача: задача,
            среда: средаЗадачи,
            запрос: запрос
          )
        )
        назначения[сторона] = назначение
        допуски[сторона] = допуск
        запросы[сторона] = запрос
      }
      let хэшПредактивации = try реестр.сохранитьПредактивацию(
        поколение: "generation.1"
      )
      let привязки: [СторонаВетвевогоФорка: ПредактивационнаяПривязкаСредыКорневойФикстуры] = [
        .левая: ПредактивационнаяПривязкаСредыКорневойФикстуры(
          идентификаторЗадачи: "task.left",
          идентификаторСреды: "host.left"
        ),
        .правая: ПредактивационнаяПривязкаСредыКорневойФикстуры(
          идентификаторЗадачи: "task.right",
          идентификаторСреды: "host.right"
        ),
      ]
      let ожидаемыйХэшКвитанцииАктивации = ресурсныйХэш(
        Data(
          "активация\u{0}поколение:generation.1\u{0}предактивация:\(хэшПредактивации)".utf8
        )
      )
      for (сторона, привязка) in привязки {
        guard
          try !реестр.разрешитьВходВОчередь(
            поколение: "generation.1",
            сторона: сторона,
            идентификаторЗадачи: привязка.идентификаторЗадачи,
            хэшКвитанции: ожидаемыйХэшКвитанцииАктивации
          )
        else {
          throw ОшибкаКорневогоРеестраЗапусков(
            "фикстура_открыла_очередь_до_активации"
          )
        }
      }
      try передАктивацией(
        реестр,
        ПредактивационноеСвидетельствоКорневойФикстуры(
          поколение: "generation.1",
          хэшПредактивации: хэшПредактивации,
          ожидаемыйХэшКвитанцииАктивации: ожидаемыйХэшКвитанцииАктивации,
          привязки: привязки
        )
      )
      for (сторона, привязка) in привязки {
        guard
          try !реестр.разрешитьВходВОчередь(
            поколение: "generation.1",
            сторона: сторона,
            идентификаторЗадачи: привязка.идентификаторЗадачи,
            хэшКвитанции: ожидаемыйХэшКвитанцииАктивации
          )
        else {
          throw ОшибкаКорневогоРеестраЗапусков(
            "фикстура_открыла_очередь_в_предактивационном_обратном_вызове"
          )
        }
      }
      let активация = try реестр.активироватьПару(
        поколение: "generation.1",
        ожидаемыйХэш: хэшПредактивации
      )
      guard активация.поколение == "generation.1",
        активация.хэшПредактивации == хэшПредактивации,
        активация.хэшКвитанции == ожидаемыйХэшКвитанцииАктивации
      else {
        throw ОшибкаКорневогоРеестраЗапусков(
          "фикстура_получила_неожиданную_квитанцию_активации"
        )
      }
      for (сторона, привязка) in привязки {
        guard
          try реестр.разрешитьВходВОчередь(
            поколение: "generation.1",
            сторона: сторона,
            идентификаторЗадачи: привязка.идентификаторЗадачи,
            хэшКвитанции: ожидаемыйХэшКвитанцииАктивации
          )
        else {
          throw ОшибкаКорневогоРеестраЗапусков(
            "фикстура_не_открыла_очередь_после_активации"
          )
        }
      }
      for допуск in допуски.values {
        guard let хэшДопуска = допуск.хэшДопуска else {
          throw ОшибкаКорневогоРеестраЗапусков(
            "фикстура_потеряла_ресурсный_допуск_после_активации"
          )
        }
        _ = try реестр.изменитьСостояниеРесурснойСессии(
          попытка: допуск.попытка,
          хэшДопуска: хэшДопуска,
          новоеСостояние: .неактивныйРебёнок
        )
      }
      let подтверждённые = try Dictionary(
        uniqueKeysWithValues: стороныФикстурыКорневогоРеестра.map { сторона in
          guard let ветвь = материализованныеВетви[сторона],
            let назначение = назначения[сторона],
            let допуск = допуски[сторона],
            let запрос = запросы[сторона],
            let хэшДопуска = допуск.хэшДопуска
          else {
            throw ОшибкаКорневогоРеестраЗапусков(
              "фикстура_не_собрала_ресурсную_host_привязку"
            )
          }
          let задача = сторона == .левая ? "task.left" : "task.right"
          let средаЗадачи = сторона == .левая ? "host.left" : "host.right"
          let корневая = ПодтверждённаяВетвьКорневойФикстуры(
            ветвь: ветвь,
            идентификаторЗадачи: задача,
            идентификаторСреды: средаЗадачи,
            хэшКонверта: запрос.хэшКонверта,
            хэшПривязки: try хэшПривязкиФикстуры(
              поколение: запрос.поколение,
              исходнаяВершина: запрос.исходнаяВершина,
              форк: запрос.форк,
              попытка: запрос.попытка,
              идентификаторЗадачи: задача,
              идентификаторСреды: средаЗадачи,
              хэшКонверта: запрос.хэшКонверта,
              идентификаторРесурсногоНазначения: назначение.идентификатор,
              хэшРесурсногоНазначения: try назначение.каноническийХэш(),
              идентификаторРесурснойПопытки: допуск.попытка,
              хэшРесурсногоДопуска: хэшДопуска
            ),
            хэшПредактивации: хэшПредактивации,
            квитанцияАктивации: активация
          )
          return (
            сторона,
            ПодтверждённаяРесурснаяВетвьКорневойФикстуры(
              корневая: корневая,
              назначение: назначение,
              допуск: допуск,
              запрос: запрос,
              вычисленныйХэшКонверта: try хэшРесурсногоКонвертаФикстуры(запрос),
              вычисленныйХэшДоказательстваАктивации:
                try хэшДоказательстваРесурснойАктивацииФикстуры(активация)
            )
          )
        }
      )
      return try тело(реестр, подтверждённые)
    }
  }


public final class АвтономнаяПоддельнаяСредаЗадач: СредаСозданияЗадач {
  private var исходы: [ИсходСозданияЗадачи]
  private var доказательства: [String: [ДоказательствоВосстановленияЗадачи]]
  public private(set) var числоВызовов: Int
  public private(set) var запросы: [ЗапросСозданияЗадачи]

  public init(исходы: [ИсходСозданияЗадачи]) {
    self.исходы = исходы
    self.доказательства = [:]
    self.числоВызовов = 0
    self.запросы = []
  }

  public func создать(_ запрос: ЗапросСозданияЗадачи) -> ИсходСозданияЗадачи {
    числоВызовов += 1
    запросы.append(запрос)
    guard !исходы.isEmpty else { return .остановленДоСвязывания }
    let исход = исходы.removeFirst()
    switch исход {
    case .точный(let задача, let среда), .потерян(let задача, let среда):
      доказательства[запрос.попытка] = [
        ДоказательствоВосстановленияЗадачи(
          запрос: запрос,
          идентификаторЗадачи: задача,
          идентификаторСреды: среда
        )
      ]
    case .неполный, .остановленДоСвязывания:
      break
    }
    return исход
  }

  public func прочитатьПопытку(
    _ запрос: ЗапросСозданияЗадачи
  ) -> [ДоказательствоВосстановленияЗадачи] {
    доказательства[запрос.попытка] ?? []
  }

  public func прочитать(попытка: String) -> ДоказательствоВосстановленияЗадачи? {
    доказательства[попытка]?.first
  }

  public func заменитьАвторитетныеРезультаты(
    попытка: String,
    результаты: [ДоказательствоВосстановленияЗадачи]
  ) {
    доказательства[попытка] = результаты
  }

  public func запрос(сторона: СторонаВетвевогоФорка) throws -> ЗапросСозданияЗадачи {
    guard let запрос = запросы.first(where: { $0.сторона == сторона }) else {
      throw ОшибкаКорневогоРеестраЗапусков("нет_запроса_создания")
    }
    return запрос
  }
}


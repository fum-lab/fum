private func гитФикстуры(_ аргументы: [String], корень: URL) throws -> String {
  let процесс = Process()
  процесс.executableURL = WritingSubnodeSystemRuntime.gitExecutableURL
  процесс.arguments = аргументы
  процесс.currentDirectoryURL = корень
  var окружение = ProcessInfo.processInfo.environment.filter {
    !$0.key.uppercased().hasPrefix("GIT_")
  }
  окружение["GIT_CONFIG_NOSYSTEM"] = "1"
  окружение["GIT_CONFIG_GLOBAL"] = WritingSubnodeSystemRuntime.nullDevicePath
  окружение["GIT_AUTHOR_DATE"] = "2001-01-01T00:00:00Z"
  окружение["GIT_COMMITTER_DATE"] = "2001-01-01T00:00:00Z"
  окружение["GIT_TERMINAL_PROMPT"] = "0"
  окружение["LC_ALL"] = "C"
  процесс.environment = окружение
  let вывод = Pipe()
  процесс.standardOutput = вывод
  процесс.standardError = вывод
  try процесс.run()
  try? вывод.fileHandleForWriting.close()
  let данные = вывод.fileHandleForReading.readDataToEndOfFile()
  процесс.waitUntilExit()
  guard процесс.terminationStatus == 0 else {
    throw ОшибкаКорневогоРеестраЗапусков("команда_гит_фикстуры_не_выполнена")
  }
  return String(decoding: данные, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)
}


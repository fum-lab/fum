  private static func выполнитьКаноническуюПару(
    повторитьАктивацию: Bool
  ) throws -> ИтогФикстурыКорневогоРеестра {
    try сКонтекстом { контекст in
      let реестр = try контекст.подготовитьРеестр()
      try контекст.материализоватьПару(реестр)
      let среда = АвтономнаяПоддельнаяСредаЗадач(исходы: [
        .точный(идентификаторЗадачи: "task.left", идентификаторСреды: "host.left"),
        .точный(идентификаторЗадачи: "task.right", идентификаторСреды: "host.right"),
      ])
      for сторона in стороныФикстурыКорневогоРеестра {
        let задача = сторона == .левая ? "task.left" : "task.right"
        try реестр.выполнитьЕдинственныйВызов(
          поколение: "generation.1", сторона: сторона, среда: среда)
        let идентификаторСреды = сторона == .левая ? "host.left" : "host.right"
        try реестр.подтвердитьСеанс(
          поколение: "generation.1", сторона: сторона, переменнаяСеанса: задача,
          билет: контекст.билет(
            задача: задача, среда: идентификаторСреды, запрос: try среда.запрос(сторона: сторона)))
      }
      let отпечаток = try реестр.сохранитьПредактивацию(поколение: "generation.1")
      var допущенные = Set<СторонаВетвевогоФорка>()
      for сторона in стороныФикстурыКорневогоРеестра {
        let задача = сторона == .левая ? "task.left" : "task.right"
        if try реестр.разрешитьВходВОчередь(
          поколение: "generation.1", сторона: сторона, идентификаторЗадачи: задача,
          хэшКвитанции: "до-CAS")
        {
          допущенные.insert(сторона)
        }
      }
      let квитанция = try реестр.активироватьПару(
        поколение: "generation.1", ожидаемыйХэш: отпечаток)
      var хэши = [квитанция.хэшКвитанции]
      if повторитьАктивацию {
        let возобновлённый = try КорневойРеестрЗапусков(каталог: контекст.адресРеестра)
        хэши.append(
          try возобновлённый.активироватьПару(поколение: "generation.1", ожидаемыйХэш: отпечаток)
            .хэшКвитанции)
      }
      for сторона in стороныФикстурыКорневогоРеестра {
        let задача = сторона == .левая ? "task.left" : "task.right"
        if try реестр.разрешитьВходВОчередь(
          поколение: "generation.1", сторона: сторона, идентификаторЗадачи: задача,
          хэшКвитанции: квитанция.хэшКвитанции)
        {
          допущенные.insert(сторона)
        }
      }
      return try итог(
        реестр, контекст: контекст, среда: среда, код: nil, допущенные: допущенные, хэши: хэши)
    }
  }

  private enum ВидВосстановления: Equatable {
    case точный
    case пустой
    case множественный
    case несовпавший
  }

  private enum ПолеПовтора: Equatable {
    case форк
    case попытка
    case источник
    case рабочаяКопия
  }

  private static func сценарийВосстановления(
    вид: ВидВосстановления
  ) throws -> ИтогФикстурыКорневогоРеестра {
    try сКонтекстом { контекст in
      let реестр = try контекст.подготовитьРеестр()
      try контекст.материализоватьПару(реестр)
      let среда = АвтономнаяПоддельнаяСредаЗадач(исходы: [
        .потерян(идентификаторЗадачи: "task.left", идентификаторСреды: "host.left")
      ])
      _ = кодОшибки {
        try реестр.выполнитьЕдинственныйВызов(
          поколение: "generation.1", сторона: .левая, среда: среда)
      }
      guard let доказательство = среда.прочитать(попытка: "attempt.left.1") else {
        throw ОшибкаКорневогоРеестраЗапусков("нет_доказательства")
      }
      switch вид {
      case .точный:
        break
      case .пустой:
        среда.заменитьАвторитетныеРезультаты(попытка: "attempt.left.1", результаты: [])
      case .множественный:
        let другое = ДоказательствоВосстановленияЗадачи(
          запрос: доказательство.запрос,
          идентификаторЗадачи: "task.other",
          идентификаторСреды: "host.other"
        )
        среда.заменитьАвторитетныеРезультаты(
          попытка: "attempt.left.1",
          результаты: [доказательство, другое]
        )
      case .несовпавший:
        var запрос = доказательство.запрос
        запрос = ЗапросСозданияЗадачи(
          поколение: запрос.поколение,
          исходнаяВершина: запрос.исходнаяВершина,
          сторона: запрос.сторона,
          попытка: "attempt.other",
          назначение: запрос.назначение,
          роль: запрос.роль,
          ребёнок: запрос.ребёнок,
          форк: запрос.форк,
          репозиторий: запрос.репозиторий,
          рабочаяСсылка: запрос.рабочаяСсылка,
          рабочаяКопия: запрос.рабочаяКопия,
          идентификаторОбщегоКаталога: запрос.идентификаторОбщегоКаталога,
          шаг: запрос.шаг,
          проект: запрос.проект,
          хэшКонверта: запрос.хэшКонверта
        )
        среда.заменитьАвторитетныеРезультаты(
          попытка: "attempt.left.1",
          результаты: [
            ДоказательствоВосстановленияЗадачи(
              запрос: запрос,
              идентификаторЗадачи: доказательство.идентификаторЗадачи,
              идентификаторСреды: доказательство.идентификаторСреды
            )
          ]
        )
      }
      let код = кодОшибки {
        try реестр.восстановитьТочнуюПопытку(
          поколение: "generation.1",
          сторона: .левая,
          среда: среда
        )
      }
      if вид == .точный {
        try реестр.подтвердитьСеанс(
          поколение: "generation.1", сторона: .левая, переменнаяСеанса: "task.left",
          билет: контекст.билет(
            задача: "task.left", среда: "host.left", запрос: try среда.запрос(сторона: .левая)))
        _ = кодОшибки {
          try реестр.выполнитьЕдинственныйВызов(
            поколение: "generation.1", сторона: .правая, среда: среда)
        }
      }
      return try итог(реестр, контекст: контекст, среда: среда, код: код)
    }
  }


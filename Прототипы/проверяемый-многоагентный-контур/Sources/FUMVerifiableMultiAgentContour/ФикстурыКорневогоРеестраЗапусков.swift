    try реестр.материализоватьИПроверитьКлон(поколение: "generation.1", сторона: .левая)
    try реестр.материализоватьИПроверитьКлон(поколение: "generation.1", сторона: .правая)
  }

  func материализоватьСвязанныеРабочиеКопии() throws {
    let левая = корень.appendingPathComponent("клон-левый-1")
    let правая = корень.appendingPathComponent("клон-правый-1")
    let промежуточнаяПравая = корень.appendingPathComponent("промежуточный-правый")
    _ = try гитФикстуры(
      ["clone", "--no-checkout", "--no-local", левыйИсточник.path, левая.path], корень: корень)
    _ = try гитФикстуры(["checkout", "--detach", вершина], корень: левая)
    _ = try гитФикстуры(["switch", "-c", "left-1"], корень: левая)
    _ = try гитФикстуры(
      ["clone", "--no-checkout", "--no-local", правыйИсточник.path, промежуточнаяПравая.path],
      корень: корень)
    _ = try гитФикстуры(
      ["worktree", "add", "-b", "right-1", правая.path, вершина], корень: промежуточнаяПравая)
  }


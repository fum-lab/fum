  private static func итог(
    _ реестр: КорневойРеестрЗапусков,
    контекст: КонтекстФикстурыКорневогоРеестра,
    среда: АвтономнаяПоддельнаяСредаЗадач,
    код: String?,
    допущенные: Set<СторонаВетвевогоФорка> = [],
    хэши: [String] = [],
    хэшиПривязок: [String] = []
  ) throws -> ИтогФикстурыКорневогоРеестра {
    let снимок = try реестр.снимок(поколение: "generation.1")
    let хэшиКонвертов = среда.запросы.map(\.хэшКонверта)
    let конвертыПолны = среда.запросы.allSatisfy {
      [
        $0.поколение, $0.исходнаяВершина, $0.попытка, $0.назначение, $0.роль,
        $0.ребёнок, $0.форк, $0.репозиторий, $0.рабочаяСсылка,
        $0.рабочаяКопия, $0.идентификаторОбщегоКаталога, $0.шаг, $0.проект,
        $0.хэшКонверта,
      ].allSatisfy { !$0.isEmpty }
    }
    return ИтогФикстурыКорневогоРеестра(
      кодОтказа: код,
      числоВызововСреды: среда.числоВызовов,
      числоАктиваций: снимок.числоАктиваций,
      допущенныеСтороны: допущенные,
      идентификаторыЗадач: снимок.задачи,
      идентификаторыСред: снимок.среды,
      идентификаторыОбщихКаталогов: снимок.общиеКаталоги,
      переносимыйПаспорт: try реестр.переносимыйПаспорт(поколение: "generation.1"),
      машинноЛокальныйКорень: контекст.корень.path,
      состоянияПопыток: снимок.состоянияПопыток,
      хэшиКвитанций: хэши,
      хэшиПривязок: хэшиПривязок,
      идентичностьКонтроллера: снимок.идентичностьКонтроллера,
      единственностьКонтроллераДоказана: снимок.идентичностьКонтроллера == .доказана,
      хэшиКонвертов: хэшиКонвертов,
      конвертыСозданияПолны: конвертыПолны
    )
  }

  private static func пустойИтог(
    контекст: КонтекстФикстурыКорневогоРеестра,
    код: String?
  ) -> ИтогФикстурыКорневогоРеестра {
    ИтогФикстурыКорневогоРеестра(
      кодОтказа: код,
      числоВызововСреды: 0,
      числоАктиваций: 0,
      допущенныеСтороны: [],
      идентификаторыЗадач: [],
      идентификаторыСред: [],
      идентификаторыОбщихКаталогов: [],
      переносимыйПаспорт: "",
      машинноЛокальныйКорень: контекст.корень.path,
      состоянияПопыток: [:],
      хэшиКвитанций: [],
      хэшиПривязок: [],
      идентичностьКонтроллера: .недоступна,
      единственностьКонтроллераДоказана: false,
      хэшиКонвертов: [],
      конвертыСозданияПолны: false
    )
  }

  private static func кодОшибки(_ тело: () throws -> Void) -> String? {
    do {
      try тело()
      return nil
    } catch let ошибка as ОшибкаКорневогоРеестраЗапусков { return ошибка.код } catch {
      return "неожиданная_ошибка"
    }
  }

  private static func сКонтекстом<Результат>(
    _ тело: (КонтекстФикстурыКорневогоРеестра) throws -> Результат
  ) throws -> Результат {
    let корень = FileManager.default.temporaryDirectory.appendingPathComponent(
      "фикстура-корневого-реестра-\(UUID().uuidString)", isDirectory: true)
    let контекст = try КонтекстФикстурыКорневогоРеестра(корень: корень)
    defer { try? FileManager.default.removeItem(at: корень) }
    return try тело(контекст)
  }

  private static func разобратьВетвиПаспорта(
    _ паспорт: String
  ) throws -> [СторонаВетвевогоФорка: String] {
    guard
      let данные = паспорт.data(using: .utf8),
      let объект = try JSONSerialization.jsonObject(with: данные) as? [String: Any],
      let ветви = объект["ветви"] as? [[String: Any]]
    else {
      throw ОшибкаКорневогоРеестраЗапусков("фикстура_не_разобрала_паспорт")
    }
    var результат: [СторонаВетвевогоФорка: String] = [:]
    for ветвь in ветви {
      guard let сторонаЗначение = ветвь["сторона"] as? String,
        let сторона = СторонаВетвевогоФорка(rawValue: сторонаЗначение),
        let общийКаталог = ветвь["общий_каталог_гит"] as? String,
        !общийКаталог.isEmpty,
        результат[сторона] == nil
      else {
        throw ОшибкаКорневогоРеестраЗапусков("фикстура_не_разобрала_ветвь_паспорта")
      }
      результат[сторона] = общийКаталог
    }
    guard Set(результат.keys) == Set(стороныФикстурыКорневогоРеестра) else {
      throw ОшибкаКорневогоРеестраЗапусков("фикстура_получила_неполную_пару_ветвей")
    }
    return результат
  }

private func хэшПривязкиФикстуры(
  поколение: String,
  исходнаяВершина: String,
  форк: String,
  попытка: String,
  идентификаторЗадачи: String,
  идентификаторСреды: String,
  хэшКонверта: String,
  идентификаторРесурсногоНазначения: String? = nil,
  хэшРесурсногоНазначения: String? = nil,
  идентификаторРесурснойПопытки: String? = nil,
  хэшРесурсногоДопуска: String? = nil
) throws -> String {
  let ресурснаяПривязка =
    идентификаторРесурсногоНазначения != nil
    || хэшРесурсногоНазначения != nil
    || идентификаторРесурснойПопытки != nil
    || хэшРесурсногоДопуска != nil
  let нагрузка = НагрузкаХэшаПривязкиФикстуры(
    схема: ресурснаяПривязка ? "корневая-привязка-задачи.2" : "корневая-привязка-задачи.1",
    поколение: поколение,
    исходнаяВершина: исходнаяВершина,
    форк: форк,
    попытка: попытка,
    идентификаторЗадачи: идентификаторЗадачи,
    идентификаторСреды: идентификаторСреды,
    хэшКонверта: хэшКонверта
  )
  let кодировщик = JSONEncoder()
  кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
  let данные: Data
  if ресурснаяПривязка {
    guard let идентификаторНазначения = идентификаторРесурсногоНазначения,
      let хэшНазначения = хэшРесурсногоНазначения,
      let идентификаторПопытки = идентификаторРесурснойПопытки,
      let хэшДопуска = хэшРесурсногоДопуска
    else {
      throw ОшибкаКорневогоРеестраЗапусков(
        "фикстура_получила_неполную_ресурсную_привязку"
      )
    }
    данные = try кодировщик.encode(
      НагрузкаХэшаПолнойРесурснойПривязкиФикстуры(
        схема: "корневая-привязка-задачи.2",
        поколение: поколение,
        исходнаяВершина: исходнаяВершина,
        форк: форк,
        попытка: попытка,
        идентификаторНазначения: идентификаторНазначения,
        хэшНазначения: хэшНазначения,
        идентификаторРесурснойПопытки: идентификаторПопытки,
        хэшРесурсногоДопуска: хэшДопуска,
        идентификаторЗадачи: идентификаторЗадачи,
        идентификаторСреды: идентификаторСреды,
        хэшКонверта: хэшКонверта
      )
    )
  } else {
    данные = try кодировщик.encode(нагрузка)
  }
  return ресурсныйХэш(данные)
}


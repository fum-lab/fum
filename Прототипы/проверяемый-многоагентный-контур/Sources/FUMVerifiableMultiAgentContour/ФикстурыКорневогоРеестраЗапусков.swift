            назначение: ветвь.идентификаторНазначения,
            роль: ветвь.роль,
            ребёнок: ветвь.идентификаторРебёнка,
            форк: ветвь.идентификаторФорка,
            репозиторий: ветвь.идентификаторРепозитория,
            рабочаяСсылка: ветвь.рабочаяСсылка,
            рабочаяКопия: ветвь.идентификаторРабочейКопии,

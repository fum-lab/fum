  private enum ПолеПовтора: Equatable {
    case форк
    case попытка
    case источник
    case рабочаяКопия
  }

  private static func сценарийВосстановления(
    вид: ВидВосстановления
  ) throws -> ИтогФикстурыКорневогоРеестра {
    try сКонтекстом { контекст in
      let реестр = try контекст.подготовитьРеестр()
      try контекст.материализоватьПару(реестр)
      let среда = АвтономнаяПоддельнаяСредаЗадач(исходы: [
        .потерян(идентификаторЗадачи: "task.left", идентификаторСреды: "host.left")
      ])
      _ = кодОшибки {
        try реестр.выполнитьЕдинственныйВызов(
          поколение: "generation.1", сторона: .левая, среда: среда)
      }
      guard let доказательство = среда.прочитать(попытка: "attempt.left.1") else {
        throw ОшибкаКорневогоРеестраЗапусков("нет_доказательства")
      }
      switch вид {
      case .точный:
        break
      case .пустой:
        среда.заменитьАвторитетныеРезультаты(попытка: "attempt.left.1", результаты: [])
      case .множественный:
        let другое = ДоказательствоВосстановленияЗадачи(
          запрос: доказательство.запрос,
          идентификаторЗадачи: "task.other",
          идентификаторСреды: "host.other"
        )
        среда.заменитьАвторитетныеРезультаты(
          попытка: "attempt.left.1",
          результаты: [доказательство, другое]
        )
      case .несовпавший:
        var запрос = доказательство.запрос
        запрос = ЗапросСозданияЗадачи(
          поколение: запрос.поколение,
          исходнаяВершина: запрос.исходнаяВершина,
          сторона: запрос.сторона,
          попытка: "attempt.other",
          назначение: запрос.назначение,
          роль: запрос.роль,
          ребёнок: запрос.ребёнок,
          форк: запрос.форк,
          репозиторий: запрос.репозиторий,
          рабочаяСсылка: запрос.рабочаяСсылка,
          рабочаяКопия: запрос.рабочаяКопия,
          идентификаторОбщегоКаталога: запрос.идентификаторОбщегоКаталога,
          шаг: запрос.шаг,
          проект: запрос.проект,
          хэшКонверта: запрос.хэшКонверта
        )
        среда.заменитьАвторитетныеРезультаты(
          попытка: "attempt.left.1",
          результаты: [
            ДоказательствоВосстановленияЗадачи(
              запрос: запрос,
              идентификаторЗадачи: доказательство.идентификаторЗадачи,
              идентификаторСреды: доказательство.идентификаторСреды
            )
          ]
        )
      }
      let код = кодОшибки {
        try реестр.восстановитьТочнуюПопытку(
          поколение: "generation.1",
          сторона: .левая,
          среда: среда
        )
      }
      if вид == .точный {
        try реестр.подтвердитьСеанс(
          поколение: "generation.1", сторона: .левая, переменнаяСеанса: "task.left",
          билет: контекст.билет(
            задача: "task.left", среда: "host.left", запрос: try среда.запрос(сторона: .левая)))
        _ = кодОшибки {
          try реестр.выполнитьЕдинственныйВызов(
            поколение: "generation.1", сторона: .правая, среда: среда)
        }
      }
      return try итог(реестр, контекст: контекст, среда: среда, код: код)
    }
  }

  private static func сценарийПовтора(пара: Bool) throws -> ИтогФикстурыКорневогоРеестра {
    try сКонтекстом { контекст in
      let реестр = try контекст.подготовитьРеестр()
      let вторая = контекст.спецификация(
        поколение: "generation.2", суффикс: "2", повторПары: пара, повторКопии: !пара)
      let код = кодОшибки { try реестр.подготовитьПоколение(вторая) }
      let среда = АвтономнаяПоддельнаяСредаЗадач(исходы: [])
      return try итог(реестр, контекст: контекст, среда: среда, код: код)
    }
  }

  private static func сценарийПовтораПоля(
    _ поле: ПолеПовтора
  ) throws -> ИтогФикстурыКорневогоРеестра {
    try сКонтекстом { контекст in
      let реестр = try контекст.подготовитьРеестр()
      let вторая = контекст.спецификация(
        поколение: "generation.2",
        суффикс: "2",
        повторФорка: поле == .форк,
        повторПопытки: поле == .попытка,
        повторИсточника: поле == .источник,
        повторФизическойКопии: поле == .рабочаяКопия
      )
      let код = кодОшибки { try реестр.подготовитьПоколение(вторая) }
      let среда = АвтономнаяПоддельнаяСредаЗадач(исходы: [])
      return try итог(реестр, контекст: контекст, среда: среда, код: код)
    }
  }

  private static func сценарийПодменыБилета(
    среда подменённаяСреда: String?,
    вершина подменённаяВершина: String?
  ) throws -> ИтогФикстурыКорневогоРеестра {
    try сКонтекстом { контекст in
      let реестр = try контекст.подготовитьРеестр()
      try контекст.материализоватьПару(реестр)
      let среда = АвтономнаяПоддельнаяСредаЗадач(исходы: [
        .точный(идентификаторЗадачи: "task.left", идентификаторСреды: "host.left")
      ])
      try реестр.выполнитьЕдинственныйВызов(
        поколение: "generation.1", сторона: .левая, среда: среда)
      var билет = контекст.билет(
        задача: "task.left", среда: "host.left", запрос: try среда.запрос(сторона: .левая))
      билет = СвидетельствоНеактивногоБилета(
        идентификаторЗадачи: билет.идентификаторЗадачи,
        идентификаторСреды: подменённаяСреда ?? билет.идентификаторСреды,
        поколение: билет.поколение,
        назначение: билет.назначение,
        роль: билет.роль,
        ребёнок: билет.ребёнок,
        форк: билет.форк,
        шаг: билет.шаг,
        проект: билет.проект,
        исходнаяВершина: подменённаяВершина ?? билет.исходнаяВершина,
        сторона: билет.сторона,
        попытка: билет.попытка,
        хэшКонверта: билет.хэшКонверта,
        репозиторий: билет.репозиторий,
        ссылка: билет.ссылка,
        рабочаяКопия: билет.рабочаяКопия,
        активен: билет.активен
      )
      let код = кодОшибки {
        try реестр.подтвердитьСеанс(
          поколение: "generation.1",
          сторона: .левая,
          переменнаяСеанса: "task.left",
          билет: билет
        )
      }
      return try итог(реестр, контекст: контекст, среда: среда, код: код)
    }
  }

  private static func сценарийАктивации(
    изменитьКлон: Bool,
    изменитьХэш: Bool
  ) throws -> ИтогФикстурыКорневогоРеестра {
    try сКонтекстом { контекст in
      let реестр = try контекст.подготовитьРеестр()
      try контекст.материализоватьПару(реестр)
      let среда = АвтономнаяПоддельнаяСредаЗадач(исходы: [
        .точный(идентификаторЗадачи: "task.left", идентификаторСреды: "host.left"),
        .точный(идентификаторЗадачи: "task.right", идентификаторСреды: "host.right"),
      ])
      for сторона in стороныФикстурыКорневогоРеестра {
        let задача = сторона == .левая ? "task.left" : "task.right"
        try реестр.выполнитьЕдинственныйВызов(
          поколение: "generation.1", сторона: сторона, среда: среда)
        try реестр.подтвердитьСеанс(
          поколение: "generation.1",
          сторона: сторона,
          переменнаяСеанса: задача,
          билет: контекст.билет(
            задача: задача, среда: сторона == .левая ? "host.left" : "host.right",
            запрос: try среда.запрос(сторона: сторона))
        )
      }
      let отпечаток = try реестр.сохранитьПредактивацию(поколение: "generation.1")
      if изменитьКлон { try контекст.перепривязатьЛевыйКлон() }
      let код = кодОшибки {
        _ = try реестр.активироватьПару(
          поколение: "generation.1",
          ожидаемыйХэш: изменитьХэш ? "sha256:\(String(repeating: "0", count: 64))" : отпечаток
        )
      }
      return try итог(реестр, контекст: контекст, среда: среда, код: код)
    }
  }

  private static func итог(
    _ реестр: КорневойРеестрЗапусков,
    контекст: КонтекстФикстурыКорневогоРеестра,
    среда: АвтономнаяПоддельнаяСредаЗадач,
    код: String?,
    допущенные: Set<СторонаВетвевогоФорка> = [],
    хэши: [String] = [],
    хэшиПривязок: [String] = []
  ) throws -> ИтогФикстурыКорневогоРеестра {
    let снимок = try реестр.снимок(поколение: "generation.1")
    let хэшиКонвертов = среда.запросы.map(\.хэшКонверта)
    let конвертыПолны = среда.запросы.allSatisfy {
      [
        $0.поколение, $0.исходнаяВершина, $0.попытка, $0.назначение, $0.роль,
        $0.ребёнок, $0.форк, $0.репозиторий, $0.рабочаяСсылка,
        $0.рабочаяКопия, $0.идентификаторОбщегоКаталога, $0.шаг, $0.проект,
        $0.хэшКонверта,
      ].allSatisfy { !$0.isEmpty }
    }
    return ИтогФикстурыКорневогоРеестра(
      кодОтказа: код,
      числоВызововСреды: среда.числоВызовов,
      числоАктиваций: снимок.числоАктиваций,
      допущенныеСтороны: допущенные,
      идентификаторыЗадач: снимок.задачи,
      идентификаторыСред: снимок.среды,
      идентификаторыОбщихКаталогов: снимок.общиеКаталоги,
      переносимыйПаспорт: try реестр.переносимыйПаспорт(поколение: "generation.1"),
      машинноЛокальныйКорень: контекст.корень.path,
      состоянияПопыток: снимок.состоянияПопыток,
      хэшиКвитанций: хэши,
      хэшиПривязок: хэшиПривязок,
      идентичностьКонтроллера: снимок.идентичностьКонтроллера,
      единственностьКонтроллераДоказана: снимок.идентичностьКонтроллера == .доказана,
      хэшиКонвертов: хэшиКонвертов,
      конвертыСозданияПолны: конвертыПолны
    )
  }

  private static func пустойИтог(
    контекст: КонтекстФикстурыКорневогоРеестра,
    код: String?
  ) -> ИтогФикстурыКорневогоРеестра {
    ИтогФикстурыКорневогоРеестра(
      кодОтказа: код,
      числоВызововСреды: 0,
      числоАктиваций: 0,
      допущенныеСтороны: [],
      идентификаторыЗадач: [],
      идентификаторыСред: [],
      идентификаторыОбщихКаталогов: [],
      переносимыйПаспорт: "",
      машинноЛокальныйКорень: контекст.корень.path,
      состоянияПопыток: [:],
      хэшиКвитанций: [],
      хэшиПривязок: [],
      идентичностьКонтроллера: .недоступна,
      единственностьКонтроллераДоказана: false,
      хэшиКонвертов: [],
      конвертыСозданияПолны: false
    )
  }

  private static func кодОшибки(_ тело: () throws -> Void) -> String? {
    do {
      try тело()
      return nil
    } catch let ошибка as ОшибкаКорневогоРеестраЗапусков { return ошибка.код } catch {
      return "неожиданная_ошибка"
    }
  }

  private static func сКонтекстом<Результат>(
    _ тело: (КонтекстФикстурыКорневогоРеестра) throws -> Результат
  ) throws -> Результат {
    let корень = FileManager.default.temporaryDirectory.appendingPathComponent(
      "фикстура-корневого-реестра-\(UUID().uuidString)", isDirectory: true)
    let контекст = try КонтекстФикстурыКорневогоРеестра(корень: корень)
    defer { try? FileManager.default.removeItem(at: корень) }
    return try тело(контекст)
  }
}

private struct КонтекстФикстурыКорневогоРеестра {
  let корень: URL
  let адресРеестра: URL
  let левыйИсточник: URL
  let правыйИсточник: URL
  let вершина: String

  init(корень: URL) throws {
    self.корень = корень
    self.адресРеестра = корень.appendingPathComponent("реестр", isDirectory: true)
    self.левыйИсточник = корень.appendingPathComponent("левый.git", isDirectory: true)
    self.правыйИсточник = корень.appendingPathComponent("правый.git", isDirectory: true)
    try FileManager.default.createDirectory(at: корень, withIntermediateDirectories: true)
    let исходник = корень.appendingPathComponent("исходник", isDirectory: true)
    _ = try гитФикстуры(["init", "--initial-branch=main", исходник.path], корень: корень)
    _ = try гитФикстуры(["config", "user.name", "FUM Fixture"], корень: исходник)
    _ = try гитФикстуры(["config", "user.email", "fixture@fum.invalid"], корень: исходник)
    try Data("база\n".utf8).write(to: исходник.appendingPathComponent("база.txt"), options: .atomic)
    _ = try гитФикстуры(["add", "--all"], корень: исходник)
    _ = try гитФикстуры(["commit", "-m", "база"], корень: исходник)
    self.вершина = try гитФикстуры(["rev-parse", "HEAD"], корень: исходник)
    _ = try гитФикстуры(["clone", "--bare", исходник.path, левыйИсточник.path], корень: корень)
    _ = try гитФикстуры(["clone", "--bare", исходник.path, правыйИсточник.path], корень: корень)
  }

  func подготовитьРеестр(
    идентичность: ИдентичностьКонтроллераЗадач = .недоступна,
    общийИсточник: Bool = false
  ) throws -> КорневойРеестрЗапусков {
    let реестр = try КорневойРеестрЗапусков(каталог: адресРеестра)
    try реестр.подготовитьПоколение(
      спецификация(
        поколение: "generation.1", суффикс: "1", идентичность: идентичность,
        общийИсточник: общийИсточник))
    return реестр
  }

  func спецификация(
    поколение: String,
    суффикс: String,
    повторПары: Bool = false,
    повторКопии: Bool = false,
    идентичность: ИдентичностьКонтроллераЗадач = .недоступна,
    общийИсточник: Bool = false,
    повторФорка: Bool = false,
    повторПопытки: Bool = false,
    повторИсточника: Bool = false,
    повторФизическойКопии: Bool = false
  ) -> СпецификацияПоколенияКорневогоЗапуска {
    let леваяПара =
      повторПары
      ? ("репозиторий.левый.1", "refs/heads/left-1")
      : ("репозиторий.левый.\(суффикс)", "refs/heads/left-\(суффикс)")
    let леваяКопия = повторКопии ? "checkout.left.1" : "checkout.left.\(суффикс)"
    let правыйИсточникФакт =
      повторИсточника
      ? левыйИсточник
      : (общийИсточник ? левыйИсточник : правыйИсточник)
    let левыйИсточникФакт = повторИсточника ? правыйИсточник : левыйИсточник
    let физическийПутьЛевойКопии =
      повторФизическойКопии
      ? корень.appendingPathComponent("клон-правый-1")
      : корень.appendingPathComponent("клон-левый-\(суффикс)")
    let левая = СпецификацияВетвиКорневогоЗапуска(
      сторона: .левая, идентификаторНазначения: "assignment.left.\(суффикс)", роль: "автор",
      идентификаторРебёнка: "child.left.\(суффикс)",
      идентификаторФорка: повторФорка ? "fork.left.1" : "fork.left.\(суффикс)",
      идентификаторРепозитория: леваяПара.0, рабочаяСсылка: леваяПара.1,
      идентификаторРабочейКопии: леваяКопия, адресИсточника: левыйИсточникФакт,
      адресРабочейКопии: физическийПутьЛевойКопии,
      идентификаторПопытки: повторПопытки ? "attempt.left.1" : "attempt.left.\(суффикс)",
      идентификаторШага: "step.left.\(суффикс)", идентификаторПроекта: "project.local")
    let правая = СпецификацияВетвиКорневогоЗапуска(
      сторона: .правая, идентификаторНазначения: "assignment.right.\(суффикс)", роль: "критик",
      идентификаторРебёнка: "child.right.\(суффикс)", идентификаторФорка: "fork.right.\(суффикс)",
      идентификаторРепозитория: "репозиторий.правый.\(суффикс)",
      рабочаяСсылка: "refs/heads/right-\(суффикс)",
      идентификаторРабочейКопии: "checkout.right.\(суффикс)", адресИсточника: правыйИсточникФакт,
      адресРабочейКопии: корень.appendingPathComponent("клон-правый-\(суффикс)"),
      идентификаторПопытки: "attempt.right.\(суффикс)", идентификаторШага: "step.right.\(суффикс)",
      идентификаторПроекта: "project.local")
    return СпецификацияПоколенияКорневогоЗапуска(
      идентификатор: поколение, исходнаяВершина: вершина, идентичностьКонтроллера: идентичность,
      идентификаторКонтроллера: идентичность == .доказана ? "desktop.singleton.1" : nil,
      ветви: [левая, правая])
  }

  func материализоватьПару(_ реестр: КорневойРеестрЗапусков) throws {
    try реестр.материализоватьИПроверитьКлон(поколение: "generation.1", сторона: .левая)
    try реестр.материализоватьИПроверитьКлон(поколение: "generation.1", сторона: .правая)
  }

  func материализоватьСвязанныеРабочиеКопии() throws {
    let левая = корень.appendingPathComponent("клон-левый-1")
    let правая = корень.appendingPathComponent("клон-правый-1")
    let промежуточнаяПравая = корень.appendingPathComponent("промежуточный-правый")
    _ = try гитФикстуры(
      ["clone", "--no-checkout", "--no-local", левыйИсточник.path, левая.path], корень: корень)
    _ = try гитФикстуры(["checkout", "--detach", вершина], корень: левая)
    _ = try гитФикстуры(["switch", "-c", "left-1"], корень: левая)
    _ = try гитФикстуры(
      ["clone", "--no-checkout", "--no-local", правыйИсточник.path, промежуточнаяПравая.path],
      корень: корень)
    _ = try гитФикстуры(
      ["worktree", "add", "-b", "right-1", правая.path, вершина], корень: промежуточнаяПравая)
  }

  func билет(
    задача: String,
    среда: String,

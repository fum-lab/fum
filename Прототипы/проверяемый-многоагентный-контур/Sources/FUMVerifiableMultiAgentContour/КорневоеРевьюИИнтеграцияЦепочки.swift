    self.родительскаяРабочаяСсылка = родительскаяРабочаяСсылка
    self.ссылкаСостояния = ссылкаСостояния
    self.целеваяСсылкаИнтеграции = целеваяСсылкаИнтеграции
    self.идентификаторЛевогоРебёнка = идентификаторЛевогоРебёнка

  private static func описаниеРазрешённыхДиапазонов(
    _ снимок: СнимокКорневогоРевьюИИнтеграцииЦепочки,
    принятыйДиапазон: [String]
  ) -> (
    вид: ВидРазрешенияКорневойИнтеграцииЦепочки,
    диапазоны: [РазрешённыйДиапазонКорневойИнтеграцииЦепочки]
  )? {
    let ревью = снимок.паспортРевью
    let коммитыРевью = Array(ревью.коммиты.prefix(принятыйДиапазон.count))
    let исходнаяСсылкаРевью =
      снимок.режимПринятия == .точныйПрефикс
      ? снимок.новаяСсылкаКандидата
      : (снимок.конвертЗапросаСлияния?.исходнаяСсылка
        ?? ревью.исходнаяСсылка)

    func диапазон(
      идентификаторРепозитория: String,
      каноническийПутьРепозитория: String?,
      исходнаяСсылка: String?,
      база: String,
      вершина: String,
      коммиты: [КоммитПринятогоДиапазонаЦепочки]
    ) -> РазрешённыйДиапазонКорневойИнтеграцииЦепочки? {
      guard let каноническийПутьРепозитория,
        let исходнаяСсылка,
        допустимыйИдентификатор(идентификаторРепозитория),
        допустимыйКаноническийПуть(каноническийПутьРепозитория),
        допустимаяСсылка(исходнаяСсылка),
        линейныйДиапазон(коммиты, база: база, вершина: вершина)
      else { return nil }
      return РазрешённыйДиапазонКорневойИнтеграцииЦепочки(
        идентификаторРепозитория: идентификаторРепозитория,
        каноническийПутьРепозитория: каноническийПутьРепозитория,
        исходнаяСсылка: исходнаяСсылка,
        база: база,
        вершина: вершина,
        коммиты: коммиты
      )
    }

    guard let модерация = снимок.паспортМодерации else {
      guard
        let единственный = диапазон(
          идентификаторРепозитория: ревью.исходныйРепозиторий,
          каноническийПутьРепозитория:
            ревью.каноническийПутьИсходногоРепозитория,
          исходнаяСсылка: исходнаяСсылкаРевью,
          база: ревью.база,
          вершина: снимок.принятаяВершина,
          коммиты: коммитыРевью
        )
      else { return nil }
      return (.линейныйДиапазон, [единственный])
    }

    let левый = модерация.левыйРезультат
    let левыйПуть =
      левый.каноническийПутьРепозитория
      ?? ревью.каноническийПутьИсходногоРепозитория
    guard
      let левыйДиапазон = диапазон(
        идентификаторРепозитория: левый.идентификаторРепозитория,
        каноническийПутьРепозитория: левыйПуть,
        исходнаяСсылка: левый.ссылкаРезультата,
        база: левый.исходнаяВершина,
        вершина: левый.вершинаРезультата,
        коммиты: левый.коммиты
      )
    else { return nil }

    switch модерация.решение {
    case .выбранЛевыйРезультат:
      return (.линейныйДиапазон, [левыйДиапазон])
    case .выбранПравыйРезультат:
      guard let правый = модерация.правыйРезультат,
        let правыйДиапазон = диапазон(
          идентификаторРепозитория: правый.идентификаторРепозитория,
          каноническийПутьРепозитория: правый.каноническийПутьРепозитория,
          исходнаяСсылка: правый.ссылкаРезультата,
          база: правый.исходнаяВершина,
          вершина: правый.вершинаРезультата,
          коммиты: правый.коммиты
        )
      else { return nil }
      return (.линейныйДиапазон, [правыйДиапазон])
    case .совместимоеОбъединение:
      guard let правый = модерация.правыйРезультат,
        let правыйДиапазон = диапазон(
          идентификаторРепозитория: правый.идентификаторРепозитория,
          каноническийПутьРепозитория: правый.каноническийПутьРепозитория,
          исходнаяСсылка: правый.ссылкаРезультата,
          база: правый.исходнаяВершина,
          вершина: правый.вершинаРезультата,
          коммиты: правый.коммиты
        )
      else { return nil }
      return (.чистоеСовместимоеОбъединение, [левыйДиапазон, правыйДиапазон])
    case .доработкаВНовомПоколенииНазначения, .отклоненыОба, .неопределённость:
      return nil
    }
  }

  private static func проверитьФорму(
    _ снимок: СнимокКорневогоРевьюИИнтеграцииЦепочки,
    нарушения: inout Set<String>
  ) {
    let ревью = снимок.паспортРевью
    let идентификаторы = [
      ревью.идентификатор, ревью.поколениеНазначения, ревью.проверяющий,
      ревью.поставщик, ревью.интегратор, ревью.исходныйРепозиторий,
      ревью.целевойРепозиторий,
    ]
    if !идентификаторы.allSatisfy(допустимыйИдентификатор)
      || !допустимаяСсылка(ревью.целеваяСсылка)
      || ревью.исходнаяСсылка.map(допустимаяСсылка) != true
      || !допустимыйОбъект(ревью.база)
      || !допустимыйОбъект(ревью.вершина)
      || !ревью.хэшиЧастныхПаспортов.allSatisfy(допустимыйХэш)
      || !допустимыйХэш(ревью.хэшКритериев)
      || !ревью.первоначальныеПроверки.allSatisfy(допустимыйХэш)
      || !ревью.повторныеПроверки.allSatisfy(допустимыйХэш)
    {
      нарушения.insert("паспорт_ревью_неверен")
    }
    if Set(ревью.хэшиЧастныхПаспортов).count != ревью.хэшиЧастныхПаспортов.count
      || Set(ревью.первоначальныеПроверки).count != ревью.первоначальныеПроверки.count
      || Set(ревью.повторныеПроверки).count != ревью.повторныеПроверки.count
      || Set(ревью.группыКорреляции).count != ревью.группыКорреляции.count
    {
      нарушения.insert("паспорт_ревью_содержит_повтор")
    }
    switch ревью.маршрут {
    case .общийВкладВЯдро:
      guard let ролеваяВершина = снимок.ожидаемаяНоваяРолеваяВершина,
        допустимыйОбъект(ролеваяВершина),
        ролеваяВершина != снимок.принятаяВершина
      else {
        нарушения.insert("ролевая_вершина_не_закреплена")
        return
      }
    case .собственныйРезультатРебёнка, .проектныйРезультат:
      if снимок.ожидаемаяНоваяРолеваяВершина != nil {
        нарушения.insert("ролевая_вершина_не_соответствует_маршруту")
      }
    }
    guard let путьИсточника = ревью.каноническийПутьИсходногоРепозитория,
      let путьЦели = ревью.каноническийПутьЦелевогоРепозитория,
      допустимыйКаноническийПуть(путьИсточника),
      допустимыйКаноническийПуть(путьЦели),
      путьИсточника == снимок.каноническийПутьИсходногоРепозитория,
      путьЦели == снимок.каноническийПутьЦелевогоРепозитория,
      ревью.исходнаяСсылка == снимок.исходнаяСсылкаКандидата
    else {
      нарушения.insert("пути_репозиториев_не_закреплены")
      return
    }
  }

  private static func проверитьАктуальность(
    _ снимок: СнимокКорневогоРевьюИИнтеграцииЦепочки,
    нарушения: inout Set<String>
  ) {
    let ревью = снимок.паспортРевью
    if ревью.база != снимок.актуальнаяБаза { нарушения.insert("база_сдвинута") }
    if ревью.вершина != снимок.актуальнаяВершина {
      нарушения.insert("вершина_сдвинута")
    }
    if ревью.хэшиЧастныхПаспортов != снимок.актуальныеХэшиЧастныхПаспортов {
      нарушения.insert("частный_паспорт_сдвинут")
    }
    if ревью.хэшКритериев != снимок.актуальныйХэшКритериев {
      нарушения.insert("критерии_сдвинуты")
    }
    if ревью.целеваяСсылка != снимок.актуальнаяЦелеваяСсылка {
      нарушения.insert("цель_сдвинута")
    }
    if ревью.поколениеНазначения != снимок.актуальноеПоколениеНазначения {
      нарушения.insert("поколение_назначения_сдвинуто")
    }
    if снимок.актуальнаяВершинаЦели != ревью.база {
      нарушения.insert("цель_не_совпадает_с_базой_диапазона")
    }
  }

  private static func проверитьРевью(
    _ ревью: ПаспортКорневогоРевьюЦепочки,
    нарушения: inout Set<String>
  ) {
    if ревью.проверяющий == ревью.поставщик
      || ревью.проверяющий == ревью.интегратор
      || ревью.поставщик == ревью.интегратор
    {
      нарушения.insert("проверяющий_не_независим")
    }
    if ревью.первоначальныеПроверки.isEmpty
      || ревью.первоначальныеПроверки != ревью.повторныеПроверки
    {
      нарушения.insert("проверки_не_повторены")
    }
    let группы = Set(ревью.группыКорреляции)
    if группы.isEmpty || ревью.замечания.isEmpty
      || !ревью.замечания.allSatisfy({ замечание in
        допустимыйИдентификатор(замечание.код)
          && !замечание.путь.isEmpty
          && !замечание.сообщение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
          && группы.contains(замечание.группаКорреляции)
      })
    {
      нарушения.insert("корреляции_не_закреплены")
    }
  }

  private static func проверитьДиапазон(
    _ ревью: ПаспортКорневогоРевьюЦепочки,
    нарушения: inout Set<String>
  ) {
    var предыдущая = ревью.база
    guard !ревью.коммиты.isEmpty else {
      нарушения.insert("диапазон_нелинеен")
      return
    }
    for коммит in ревью.коммиты {
      guard допустимыйОбъект(коммит.объект), коммит.родители == [предыдущая] else {
        нарушения.insert("диапазон_нелинеен")
        return
      }
      предыдущая = коммит.объект
    }
    if предыдущая != ревью.вершина
      || ревью.хэшиЧастныхПаспортов.count != ревью.коммиты.count
    {
      нарушения.insert("диапазон_нелинеен")
    }
  }

  private static func проверитьМодерацию(
    _ модерация: ПаспортМодерацииКорневойЦепочки,
    ревью: ПаспортКорневогоРевьюЦепочки,
    нарушения: inout Set<String>
  ) {
    let левый = модерация.левыйРезультат
    let правый = модерация.правыйРезультат
    if модерация.идентификаторЛевогоРебёнка != левый.идентификаторФорка
      || модерация.идентификаторЛевогоРепозитория != левый.идентификаторРепозитория
      || модерация.леваяБаза != левый.исходнаяВершина
      || модерация.леваяРабочаяСсылка != левый.рабочаяСсылка
      || модерация.леваяВершина != левый.вершинаРезультата
      || модерация.леваяСсылкаРезультата != левый.ссылкаРезультата
      || модерация.идентификаторПравогоРебёнка != правый?.идентификаторФорка
      || модерация.идентификаторПравогоРепозитория != правый?.идентификаторРепозитория
      || модерация.праваяБаза != правый?.исходнаяВершина
      || модерация.праваяРабочаяСсылка != правый?.рабочаяСсылка
      || модерация.праваяВершина != правый?.вершинаРезультата
      || модерация.праваяСсылкаРезультата != правый?.ссылкаРезультата
    {
      нарушения.insert("дубли_полей_модерации_не_совпадают")
    }
    if ![
      модерация.идентификаторРодителяМодератора,
      модерация.идентификаторПопытки,
      модерация.поколениеНазначения,
      модерация.идентификаторЛевогоРебёнка,
      модерация.идентификаторЛевогоРепозитория,
    ].allSatisfy(допустимыйИдентификатор)
      || !допустимаяСсылка(модерация.родительскаяРабочаяСсылка)
      || !допустимаяСсылка(модерация.ссылкаСостояния)
      || !допустимаяСсылка(модерация.целеваяСсылкаИнтеграции)
      || !допустимаяСсылка(модерация.леваяРабочаяСсылка)
      || !допустимаяСсылка(модерация.леваяСсылкаРезультата)
      || !допустимыйОбъект(модерация.провереннаяБаза)
      || !допустимыйОбъект(модерация.леваяБаза)
      || !допустимыйОбъект(модерация.леваяВершина)
    {
      нарушения.insert("паспорт_модерации_неверен")
    }
    if модерация.поколениеНазначения != ревью.поколениеНазначения
      || модерация.провереннаяБаза != ревью.база
      || модерация.леваяБаза != модерация.провереннаяБаза
      || модерация.леваяВершина != ревью.вершина
      || левый.идентификаторРепозитория != ревью.исходныйРепозиторий
      || левый.каноническийПутьРепозитория
        != ревью.каноническийПутьИсходногоРепозитория
      || левый.ссылкаРезультата != ревью.исходнаяСсылка
      || модерация.хэшКритериев != ревью.хэшКритериев
      || модерация.целеваяСсылкаИнтеграции != модерация.родительскаяРабочаяСсылка
    {
      нарушения.insert("модерация_не_связана_с_ревью")
    }
    if модерация.идентификаторРодительскогоРепозитория != ревью.целевойРепозиторий
      || модерация.каноническийПутьРодительскогоРепозитория
        != ревью.каноническийПутьЦелевогоРепозитория
    {
      нарушения.insert("модерация_не_связана_с_репозиторием")
    }
    if левый.коммиты != ревью.коммиты
      || !линейныйДиапазон(
        левый.коммиты,
        база: левый.исходнаяВершина,
        вершина: левый.вершинаРезультата
      )
    {
      нарушения.insert("левый_диапазон_модерации_не_совпадает")
    }
    let правыеПоляПрисутствуют = [
      модерация.идентификаторПравогоРебёнка,
      модерация.идентификаторПравогоРепозитория,
      модерация.праваяБаза,
      модерация.праваяРабочаяСсылка,
      модерация.праваяВершина,
      модерация.праваяСсылкаРезультата,
    ].map { $0 != nil }
    if Set(правыеПоляПрисутствуют).count > 1 {
      нарушения.insert("паспорт_модерации_неверен")
    }
    if let идентификатор = модерация.идентификаторПравогоРебёнка,
      !допустимыйИдентификатор(идентификатор)
        || идентификатор == модерация.идентификаторЛевогоРебёнка
    {
      нарушения.insert("паспорт_модерации_неверен")
    }
    if let репозиторий = модерация.идентификаторПравогоРепозитория,
      !допустимыйИдентификатор(репозиторий)
        || репозиторий == модерация.идентификаторЛевогоРепозитория
    {
      нарушения.insert("паспорт_модерации_неверен")
    }
    if let база = модерация.праваяБаза, база != модерация.провереннаяБаза {
      нарушения.insert("модерация_не_связана_с_ревью")
    }
    if let ссылка = модерация.праваяРабочаяСсылка, !допустимаяСсылка(ссылка) {
      нарушения.insert("паспорт_модерации_неверен")
    }
    if let правая = модерация.праваяВершина, !допустимыйОбъект(правая) {
      нарушения.insert("паспорт_модерации_неверен")
    }
    if let ссылка = модерация.праваяСсылкаРезультата, !допустимаяСсылка(ссылка) {
      нарушения.insert("паспорт_модерации_неверен")
    }
    if let правый,
      !линейныйДиапазон(
        правый.коммиты,
        база: правый.исходнаяВершина,
        вершина: правый.вершинаРезультата
      )
    {
      нарушения.insert("правый_диапазон_модерации_нелинеен")
    }
    if [.выбранПравыйРезультат, .совместимоеОбъединение].contains(модерация.решение),
      правый == nil
        || правый?.каноническийПутьРепозитория.map(допустимыйКаноническийПуть) != true
    {
      нарушения.insert("правый_репозиторий_модерации_не_закреплён")
    }
  }

  private static func диапазоныПринятия(
    _ снимок: СнимокКорневогоРевьюИИнтеграцииЦепочки,
    нарушения: inout Set<String>
  ) -> ([String], [String]) {
    let объекты = снимок.паспортРевью.коммиты.map(\.объект)
    switch снимок.режимПринятия {
    case .всяЦепочка:
      if снимок.принятаяВершина != снимок.паспортРевью.вершина {
        нарушения.insert("принятие_не_соответствует_диапазону")
      }
      return (объекты, [])
    case .точныйПрефикс:
      guard let позиция = объекты.firstIndex(of: снимок.принятаяВершина) else {
        нарушения.insert("принятие_не_соответствует_диапазону")
        return ([], объекты)
      }
      return (
        Array(объекты.prefix(through: позиция)),
        Array(объекты.dropFirst(позиция + 1))
      )
    }
  }

  private static func проверитьМаршрутИЗапросСлияния(
    _ снимок: СнимокКорневогоРевьюИИнтеграцииЦепочки,
    принятыйДиапазон: [String],
    нарушения: inout Set<String>
  ) {
    let ревью = снимок.паспортРевью
    switch ревью.маршрут {
    case .собственныйРезультатРебёнка:
      if ревью.исходныйРепозиторий != ревью.целевойРепозиторий {
        нарушения.insert("маршрут_результата_неверен")
      }
      if снимок.конвертЗапросаСлияния != nil {
        нарушения.insert("запрос_слияния_не_соответствует_маршруту")
      }
    case .проектныйРезультат:
      if ревью.исходныйРепозиторий == ревью.целевойРепозиторий {
        нарушения.insert("маршрут_результата_неверен")
      }
      if снимок.конвертЗапросаСлияния != nil {
        нарушения.insert("запрос_слияния_не_соответствует_маршруту")
      }
    case .общийВкладВЯдро:
      guard let конверт = снимок.конвертЗапросаСлияния else {
        нарушения.insert("запрос_слияния_не_действителен")
        return
      }
      проверитьКонверт(
        конверт,
        ревью: ревью,
        ожидаемаяВершина: ревью.вершина,
        ожидаемыйДиапазон: ревью.коммиты.map(\.объект),
        ожидаемаяИсходнаяСсылка: nil,
        нарушения: &нарушения
      )
      _ = принятыйДиапазон
    }
  }

  private static func проверитьКонверт(
    _ конверт: КонвертЗапросаСлиянияЦепочки,
    ревью: ПаспортКорневогоРевьюЦепочки,
    ожидаемаяВершина: String,
    ожидаемыйДиапазон: [String],
    ожидаемаяИсходнаяСсылка: String?,
    нарушения: inout Set<String>
  ) {
    if конверт.состояние != .открыт
      || конверт.поставщик.isEmpty
      || конверт.исходныйРепозиторий != ревью.исходныйРепозиторий
      || конверт.целевойРепозиторий != ревью.целевойРепозиторий
      || конверт.каноническийПутьИсходногоРепозитория
        != ревью.каноническийПутьИсходногоРепозитория
      || конверт.каноническийПутьЦелевогоРепозитория
        != ревью.каноническийПутьЦелевогоРепозитория
      || конверт.целеваяСсылка != ревью.целеваяСсылка
      || конверт.поколениеНазначения != ревью.поколениеНазначения
      || конверт.база != ревью.база
      || конверт.вершина != ожидаемаяВершина
      || конверт.диапазон != ожидаемыйДиапазон
      || !допустимаяСсылка(конверт.исходнаяСсылка)
      || !допустимаяСсылка(конверт.целеваяСсылка)
      || !допустимыйИдентификатор(конверт.идентификатор)
      || !допустимыйХэш(конверт.хэшПубликационногоАудита)
      || конверт.числоАвторитетныхЧтений < 0
      || конверт.числоАвторитетныхЧтений > 1
      || ожидаемаяИсходнаяСсылка.map({ $0 != конверт.исходнаяСсылка }) == true
    {
      нарушения.insert("запрос_слияния_не_действителен")
    }
    if конверт.числоСозданий != 1 {
      нарушения.insert("повторное_создание_запроса_слияния")
    }
  }

  private static func проверитьПеревыпускПрефикса(
    _ снимок: СнимокКорневогоРевьюИИнтеграцииЦепочки,
    принятыйДиапазон: [String],
    нарушения: inout Set<String>
  ) {
    guard снимок.режимПринятия == .точныйПрефикс else {
      if снимок.новоеПоколениеКандидата != nil
        || снимок.новаяСсылкаКандидата != nil
        || снимок.новыйХэшПаспортаКандидата != nil
        || снимок.новыйКонвертПрефикса != nil
      {
        нарушения.insert("перевыпуск_без_точного_префикса")
      }
      return
    }
    if снимок.паспортМодерации != nil {
      нарушения.insert("префикс_не_совместим_с_решением_модератора")
    }
    guard let поколение = снимок.новоеПоколениеКандидата,
      let ссылка = снимок.новаяСсылкаКандидата,
      let хэшПаспорта = снимок.новыйХэшПаспортаКандидата,
      допустимыйИдентификатор(поколение),
      допустимаяСсылка(ссылка),
      ссылка.hasPrefix("refs/heads/"),
      допустимыйХэш(хэшПаспорта)
    else {
      нарушения.insert("префикс_не_перевыпущен")
      return
    }
    if поколение == снимок.исходноеПоколениеКандидата
      || ссылка == снимок.исходнаяСсылкаКандидата
      || хэшПаспорта == снимок.исходныйХэшПаспортаКандидата
    {
      нарушения.insert("префикс_переиспользует_старое_значение")
    }
    if снимок.паспортРевью.маршрут == .общийВкладВЯдро {
      guard let новый = снимок.новыйКонвертПрефикса else {
        нарушения.insert("префикс_не_перевыпущен")
        return
      }
      проверитьКонверт(
        новый,
        ревью: снимок.паспортРевью,
        ожидаемаяВершина: снимок.принятаяВершина,
        ожидаемыйДиапазон: принятыйДиапазон,
        ожидаемаяИсходнаяСсылка: ссылка,
        нарушения: &нарушения
      )
      if новый.идентификатор == снимок.конвертЗапросаСлияния?.идентификатор {
        нарушения.insert("префикс_переиспользует_старое_значение")
      }
    } else if снимок.новыйКонвертПрефикса != nil {
      нарушения.insert("запрос_слияния_не_соответствует_маршруту")
    }
  }

  private static func вершинаПослеМодерации(
    _ модерация: ПаспортМодерацииКорневойЦепочки?,
    принятаяВершина: String,
    нарушения: inout Set<String>
  ) -> String? {
    guard let модерация else { return принятаяВершина }
    switch модерация.решение {
    case .выбранЛевыйРезультат:
      if модерация.интеграционнаяВершина != nil
        || !модерация.родителиИнтеграционнойВершины.isEmpty
      {
        нарушения.insert("граница_объединения_неверна")
      }
      return принятаяВершина
    case .выбранПравыйРезультат:
      guard let правая = модерация.праваяВершина else {
        нарушения.insert("решение_модератора_неполно")
        return nil
      }
      return правая
    case .совместимоеОбъединение:
      guard let правая = модерация.праваяВершина,
        let интеграционная = модерация.интеграционнаяВершина,
        допустимыйОбъект(интеграционная),
        интеграционная != модерация.леваяВершина,
        интеграционная != правая,
        модерация.родителиИнтеграционнойВершины == [модерация.леваяВершина, правая]
      else {
        нарушения.insert("граница_объединения_неверна")
        return nil
      }
      return интеграционная
    case .доработкаВНовомПоколенииНазначения, .отклоненыОба, .неопределённость:
      return nil
    }
  }

  private static func допустимыйИдентификатор(_ значение: String) -> Bool {
    let байты = значение.utf8
    return !байты.isEmpty && байты.count <= 256
      && значение == значение.precomposedStringWithCanonicalMapping
      && !значение.contains(where: { $0.isWhitespace || $0.isNewline })
  }

  private static func допустимыйКаноническийПуть(_ значение: String) -> Bool {
    guard значение.hasPrefix("/"),
      значение == значение.precomposedStringWithCanonicalMapping,
      !значение.contains("\0")
    else { return false }
    return URL(fileURLWithPath: значение).standardizedFileURL.path == значение
  }

  private static func линейныйДиапазон(
    _ коммиты: [КоммитПринятогоДиапазонаЦепочки],
    база: String,
    вершина: String
  ) -> Bool {
    guard !коммиты.isEmpty else { return false }
    var предыдущая = база
    for коммит in коммиты {
      guard допустимыйОбъект(коммит.объект), коммит.родители == [предыдущая] else {
        return false
      }
      предыдущая = коммит.объект
    }
    return предыдущая == вершина
  }

  private static func допустимыйОбъект(_ значение: String) -> Bool {
    (значение.count == 40 || значение.count == 64)
      && значение.allSatisfy { "0123456789abcdef".contains($0) }
  }

  private static func допустимыйХэш(_ значение: String) -> Bool {
    guard значение.hasPrefix("sha256:") else { return false }
    let остаток = значение.dropFirst("sha256:".count)
    return остаток.count == 64 && остаток.allSatisfy { "0123456789abcdef".contains($0) }
  }

  private static func допустимаяСсылка(_ значение: String) -> Bool {
    guard значение.hasPrefix("refs/"), значение.utf8.count <= 1_024 else { return false }
    let запрещённые = ["..", "//", "@{", "\\", " ", "~", "^", ":", "?", "*"]
    return !значение.hasSuffix("/") && !значение.hasSuffix(".")
      && !значение.hasSuffix(".lock")
      && !запрещённые.contains(where: значение.contains)
  }
}

private func каноническийХэшКорневойИнтеграции<Значение: Encodable>(
  _ значение: Значение
) throws -> String {
  let кодировщик = JSONEncoder()
  кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
  let данные = try кодировщик.encode(значение)
  return "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}


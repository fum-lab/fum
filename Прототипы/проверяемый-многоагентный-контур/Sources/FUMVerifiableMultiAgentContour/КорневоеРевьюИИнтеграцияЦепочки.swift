      self.правыйРезультат = ЗамороженныйРезультатРебёнкаДляМодерацииЦепочки(
        идентификаторФорка: идентификаторПравогоРебёнка ?? "fork.правый",
        идентификаторРепозитория:
          идентификаторПравогоРепозитория ?? "репозиторий.правый",
        исходнаяВершина: праваяБаза ?? провереннаяБаза,
        рабочаяСсылка: праваяРабочаяСсылка ?? "refs/heads/правая",
        ссылкаРезультата: ссылкаРезультата,
        вершинаРезультата: вершинаРезультата

public enum РедукторКорневойИнтеграцииЦепочки {
  public static func применить(
    _ событие: ОграждённоеСобытиеКорневойИнтеграцииЦепочки,
    к состояние: СостояниеКорневойИнтеграцииЦепочки
  ) -> СостояниеКорневойИнтеграцииЦепочки {
    guard состояние.разрешение.действительно else {
      return отказать(состояние, "ограждение_решения_не_совпадает")
    }

    func проверитьХэш(_ хэш: String) -> СостояниеКорневойИнтеграцииЦепочки? {
      хэш == состояние.хэшРешения
        ? nil : отказать(состояние, "ограждение_решения_не_совпадает")
    }

    switch событие {
    case .сравнитьИЗаменитьЦель(
      let хэш, let ссылка, let ожидаемая, let наблюдаемая, let новая
    ),
      .зафиксироватьПроигрышСравненияИЗамены(
        let хэш, let ссылка, let ожидаемая, let наблюдаемая, let новая
      ):
      if let отказ = проверитьХэш(хэш) { return отказ }
      guard ссылка == состояние.разрешение.целеваяСсылка else {
        return отказать(состояние, "ограждение_ссылки_не_совпадает")
      }
      guard ожидаемая == состояние.ожидаемаяВершинаЦели,
        новая == состояние.принятаяВершина,
        состояние.текущаяВершинаЦели == ожидаемая
      else { return отказать(состояние, "ограждение_вершин_не_совпадает") }
      if case .зафиксироватьПроигрышСравненияИЗамены = событие {
        return применить(
          .зафиксироватьПроигрышСравненияИЗамены(
            наблюдаемаяВершина: наблюдаемая
          ),
          к: состояние
        )
      }
      return применить(
        .сравнитьИЗаменитьЦель(наблюдаемаяВершина: наблюдаемая),
        к: состояние
      )

    case .обновитьСсылкуРебёнкаВСборке(
      let хэш, let ожидаемаяСборка, let наблюдаемаяСборка,
      let ожидаемыйРебёнок, let наблюдаемыйРебёнок, let новыйРебёнок
    ):
      if let отказ = проверитьХэш(хэш) { return отказ }
      guard ожидаемаяСборка == состояние.разрешение.ожидаемаяВершинаСборки,
        ожидаемыйРебёнок
          == (состояние.разрешение.ожидаемаяВершинаРебёнкаВСборке
            ?? состояние.разрешение.ожидаемаяВершинаСборки),
        состояние.вершинаРебёнкаВСборке == ожидаемыйРебёнок,
        новыйРебёнок == состояние.принятаяВершина
      else { return отказать(состояние, "ограждение_вершин_не_совпадает") }
      guard наблюдаемаяСборка == ожидаемаяСборка else {
        return состояние.изменив(состояниеПерехода: .конфликтСсылкиСборки)
      }
      return применить(
        .обновитьСсылкуРебёнкаВСборке(
          ожидаемаяВершина: ожидаемыйРебёнок,
          наблюдаемаяВершина: наблюдаемыйРебёнок
        ),
        к: состояние
      )

    case .синхронизироватьРебёнка(
      let хэш, let ядро, let роль, let родители
    ):
      if let отказ = проверитьХэш(хэш) { return отказ }
      guard let закреплённаяРоль = состояние.разрешение.ожидаемаяНоваяРолеваяВершина,
        ядро == состояние.принятаяВершина,
        роль == закреплённаяРоль,
        родители == [ядро]
      else { return отказать(состояние, "ограждение_вершин_не_совпадает") }
      return применить(
        .синхронизироватьРебёнка(
          зеркальнаяВершинаЯдра: ядро,
          новаяРолеваяВершина: роль,
          родителиРолевойВершины: родители
        ),
        к: состояние
      )

    case .согласоватьСсылкиСборки(
      let хэш, let ожидаемаяСборка, let наблюдаемаяСборка,
      let ожидаемоеЯдро, let наблюдаемоеЯдро, let новоеЯдро,
      let ожидаемыйРебёнок, let наблюдаемыйРебёнок, let новыйРебёнок,
      let ядроУжеТочно
    ):
      if let отказ = проверитьХэш(хэш) { return отказ }
      guard ожидаемаяСборка == состояние.разрешение.ожидаемаяВершинаСборки,
        наблюдаемаяСборка == ожидаемаяСборка,
        ожидаемоеЯдро == состояние.разрешение.ожидаемаяВершинаЯдраВСборке,
        ожидаемыйРебёнок == состояние.разрешение.ожидаемаяВершинаРебёнкаВСборке,
        состояние.вершинаЯдраВСборке == ожидаемоеЯдро,
        состояние.вершинаРебёнкаВСборке == ожидаемыйРебёнок,
        новоеЯдро == состояние.принятаяВершина,
        новыйРебёнок == состояние.синхронизированнаяВершинаРебёнка,
        ядроУжеТочно == (наблюдаемоеЯдро == новоеЯдро)
      else { return отказать(состояние, "ограждение_вершин_не_совпадает") }
      guard наблюдаемоеЯдро == ожидаемоеЯдро || ядроУжеТочно,
        наблюдаемыйРебёнок == ожидаемыйРебёнок
      else {
        return состояние.изменив(состояниеПерехода: .конфликтСсылокСборки)
      }
      return состояние.изменив(
        состояниеПерехода: .завершено,
        вершинаЯдраВСборке: .some(новоеЯдро),
        вершинаРебёнкаВСборке: .some(новыйРебёнок)
      )

    case .исходСравненияНеизвестен(let хэш, let наблюдаемая):
      if let отказ = проверитьХэш(хэш) { return отказ }
      return применить(
        .исходСравненияНеизвестен(последняяНаблюдаемаяВершина: наблюдаемая),
        к: состояние
      )
    case .обнаружитьНеизвестныйКонфликт(let хэш):
      if let отказ = проверитьХэш(хэш) { return отказ }
      return применить(.обнаружитьНеизвестныйКонфликт, к: состояние)
    case .зафиксироватьКонфликтИнтеграции(let хэш):
      if let отказ = проверитьХэш(хэш) { return отказ }
      return применить(.зафиксироватьКонфликтИнтеграции, к: состояние)
    case .применитьАвтоматическоеРазрешениеКонфликтаСсылкиСборки(let хэш):
      if let отказ = проверитьХэш(хэш) { return отказ }
      return применить(
        .применитьАвтоматическоеРазрешениеКонфликтаСсылкиСборки,
        к: состояние
      )
    }
  }

  private static func отказать(
    _ состояние: СостояниеКорневойИнтеграцииЦепочки,
    _ код: String
  ) -> СостояниеКорневойИнтеграцииЦепочки {
    состояние.изменив(кодОтказа: .some(код))
  }

  static func применить(
    _ событие: СобытиеКорневойИнтеграцииЦепочки,
    к состояние: СостояниеКорневойИнтеграцииЦепочки
  ) -> СостояниеКорневойИнтеграцииЦепочки {
    guard состояние.разрешение.действительно else {
      return состояние.изменив(состояниеПерехода: .решениеНеПринято)
    }
    switch событие {
    case .сравнитьИЗаменитьЦель(let наблюдаемаяВершина):
      guard состояние.состояниеПерехода == .подготовлено else { return состояние }
      guard наблюдаемаяВершина == состояние.ожидаемаяВершинаЦели else {
        return состояние.изменив(
          состояниеПерехода: .сравнениеПроиграно,
          текущаяВершинаЦели: наблюдаемаяВершина
        )
      }
      let следующийИсход: СостояниеПереходаКорневойИнтеграцииЦепочки
      switch состояние.маршрут {
      case .собственныйРезультатРебёнка:
        следующийИсход = .принятоВРебёнкеОбновлениеСсылкиСборкиОжидается
      case .проектныйРезультат:
        следующийИсход = .принятоВПроектеОбновлениеСсылкиСборкиОжидается
      case .общийВкладВЯдро:
        следующийИсход = .принятоВЯдреСинхронизацияРебёнкаОжидается
      }
      return состояние.изменив(
        состояниеПерехода: следующийИсход,
        текущаяВершинаЦели: состояние.принятаяВершина
      )

    case .зафиксироватьПроигрышСравненияИЗамены(let наблюдаемаяВершина):
      guard состояние.состояниеПерехода == .подготовлено else { return состояние }
      return состояние.изменив(
        состояниеПерехода: .сравнениеПроиграно,
        текущаяВершинаЦели: наблюдаемаяВершина
      )

    case .обнаружитьНеизвестныйКонфликт:
      guard состояние.состояниеПерехода == .подготовлено else { return состояние }
      return состояние.изменив(состояниеПерехода: .неизвестныйКонфликт)

    case .исходСравненияНеизвестен(let последняяНаблюдаемаяВершина):
      guard состояние.состояниеПерехода == .подготовлено else { return состояние }
      return состояние.изменив(
        состояниеПерехода: .исходСравненияНеизвестен,
        текущаяВершинаЦели: последняяНаблюдаемаяВершина
      )

    case .зафиксироватьКонфликтИнтеграции:
      guard состояние.состояниеПерехода == .подготовлено else { return состояние }
      return состояние.изменив(состояниеПерехода: .конфликтИнтеграции)

    case .применитьАвтоматическоеРазрешениеКонфликтаСсылкиСборки:
      return состояние.изменив(
        кодОтказа: .some("автоматическое_разрешение_ссылки_сборки_запрещено")
      )

    case .обновитьСсылкуРебёнкаВСборке(
      let ожидаемаяВершина,
      let наблюдаемаяВершина
    ):
      guard
        состояние.состояниеПерехода
          == .принятоВРебёнкеОбновлениеСсылкиСборкиОжидается
          || состояние.состояниеПерехода
            == .принятоВПроектеОбновлениеСсылкиСборкиОжидается
      else { return состояние }
      guard наблюдаемаяВершина == ожидаемаяВершина else {
        return состояние.изменив(состояниеПерехода: .конфликтСсылкиСборки)
      }
      return состояние.изменив(
        состояниеПерехода: .завершено,
        вершинаРебёнкаВСборке: .some(состояние.принятаяВершина)
      )

    case .синхронизироватьРебёнка(
      let зеркальнаяВершинаЯдра,
      let новаяРолеваяВершина,
      let родителиРолевойВершины
    ):
      guard
        состояние.состояниеПерехода
          == .принятоВЯдреСинхронизацияРебёнкаОжидается
      else { return состояние }
      guard зеркальнаяВершинаЯдра == состояние.принятаяВершина,
        новаяРолеваяВершина != состояние.принятаяВершина,
        родителиРолевойВершины == [состояние.принятаяВершина]
      else {
        return состояние.изменив(состояниеПерехода: .синхронизацияРебёнкаОтклонена)
      }
      return состояние.изменив(
        состояниеПерехода: .согласованиеСсылокСборкиОжидается,
        синхронизированнаяВершинаРебёнка: .some(новаяРолеваяВершина)
      )

    case .согласоватьСсылкиСборки(
      let ожидаемоеЯдро,
      let наблюдаемоеЯдро,
      let новоеЯдро,
      let ожидаемыйРебёнок,
      let наблюдаемыйРебёнок,
      let новыйРебёнок
    ):
      guard состояние.состояниеПерехода == .согласованиеСсылокСборкиОжидается,
        let синхронизированныйРебёнок = состояние.синхронизированнаяВершинаРебёнка
      else { return состояние }
      let ядроУжеТочно = наблюдаемоеЯдро == состояние.принятаяВершина
      guard состояние.вершинаЯдраВСборке == наблюдаемоеЯдро,
        состояние.вершинаРебёнкаВСборке == наблюдаемыйРебёнок,
        наблюдаемоеЯдро == ожидаемоеЯдро || ядроУжеТочно,
        наблюдаемыйРебёнок == ожидаемыйРебёнок,
        новоеЯдро == состояние.принятаяВершина,
        новыйРебёнок == синхронизированныйРебёнок,
        новыйРебёнок != состояние.принятаяВершина
      else {
        return состояние.изменив(состояниеПерехода: .конфликтСсылокСборки)
      }
      return состояние.изменив(
        состояниеПерехода: .завершено,
        вершинаЯдраВСборке: .some(новоеЯдро),
        вершинаРебёнкаВСборке: .some(новыйРебёнок)
      )
    }
  }
}

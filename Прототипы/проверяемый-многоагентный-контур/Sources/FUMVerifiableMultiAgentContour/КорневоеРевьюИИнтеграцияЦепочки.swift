public enum ПроверкаКорневогоРевьюИИнтеграцииЦепочки {
  public static func проверить(
    _ снимок: СнимокКорневогоРевьюИИнтеграцииЦепочки
  ) -> ОтчётКорневогоРевьюИИнтеграцииЦепочки {
    let ревью = снимок.паспортРевью
    let модерация = снимок.паспортМодерации
    var нарушения: Set<String> = []

    проверитьФорму(снимок, нарушения: &нарушения)
    проверитьАктуальность(снимок, нарушения: &нарушения)
    проверитьРевью(ревью, нарушения: &нарушения)
    проверитьДиапазон(ревью, нарушения: &нарушения)
    if let модерация {
      проверитьМодерацию(модерация, ревью: ревью, нарушения: &нарушения)
    }

    let (принятыйДиапазон, непринятыйОстаток) = диапазоныПринятия(
      снимок,
      нарушения: &нарушения
    )
    проверитьМаршрутИЗапросСлияния(
      снимок,
      принятыйДиапазон: принятыйДиапазон,
      нарушения: &нарушения
    )
    проверитьПеревыпускПрефикса(
      снимок,
      принятыйДиапазон: принятыйДиапазон,
      нарушения: &нарушения
    )
    проверитьПоколениеДоработки(снимок, нарушения: &нарушения)

    let интегрируемаяВершина = вершинаПослеМодерации(
      модерация,
      принятаяВершина: снимок.принятаяВершина,
      нарушения: &нарушения
    )
    let решениеПринято = ревью.исход == .принято && интегрируемаяВершина != nil
    let разрешение: РазрешениеИнтеграцииПринятогоДиапазона?
    if нарушения.isEmpty, решениеПринято, let интегрируемаяВершина {
      разрешение = создатьРазрешение(
        для: снимок,
        новаяВершина: интегрируемаяВершина,
        принятыйДиапазон: принятыйДиапазон
      )
    } else {
      разрешение = nil
    }

    let решение: РешениеПроверкиКорневогоРевьюИИнтеграцииЦепочки
    if !нарушения.isEmpty {
      решение = .недопустимо
    } else if разрешение == nil {
      решение = .решениеНеПринято
    } else {
      решение = .допустимо
    }
    return ОтчётКорневогоРевьюИИнтеграцииЦепочки(
      решение: решение,
      кодыНарушений: нарушения,
      разрешение: разрешение,
      состояниеПерехода: разрешение == nil ? .решениеНеПринято : .подготовлено,
      непринятыйОстаток: непринятыйОстаток,
      дочерниеСсылкиНеИзменяются:
        нарушения.isEmpty && модерация?.решение == .совместимоеОбъединение,
      поколениеДоработки:
        ревью.исход == .наДоработку ? снимок.новоеПоколениеДоработки : nil
    )
  }

  private static func проверитьПоколениеДоработки(
    _ снимок: СнимокКорневогоРевьюИИнтеграцииЦепочки,
    нарушения: inout Set<String>
  ) {
    if снимок.паспортРевью.исход == .наДоработку {
      guard let поколение = снимок.новоеПоколениеДоработки,
        допустимыйИдентификатор(поколение),
        поколение != снимок.паспортРевью.поколениеНазначения
      else {
        нарушения.insert("доработка_не_создала_новое_поколение")
        return
      }
    } else if снимок.новоеПоколениеДоработки != nil {
      нарушения.insert("поколение_доработки_без_доработки")
    }
  }


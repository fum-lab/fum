public struct ФикстураУниверсальногоФоркИсполнителя: Sendable {
  public let регистрация: Data
  public let контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя

  public init(
    регистрация: Data,
    контекст: КонтекстПроверкиУниверсальногоФоркИсполнителя
  ) {
    self.регистрация = регистрация
    self.контекст = контекст
  }
}

public enum ОшибкаФикстурыУниверсальногоФоркИсполнителя:
  Error, CustomStringConvertible, Sendable
{
  case неизвестнаяФикстура(String)
  case командаЗавершиласьНеудачно([String], Int32, String)
  case невернаяКодировка([String])
  case исполняемыйФайлНеНайден(String)
  case кореньЧекаутаНеНайден
  case неверныйОбъект

  public var description: String {
    switch self {
    case .неизвестнаяФикстура(let имя):
      "Неизвестная фикстура универсального fork-исполнителя: \(имя)."
    case .командаЗавершиласьНеудачно(let аргументы, let код, let вывод):
      "Локальная команда git \(аргументы.joined(separator: " ")) завершилась с кодом \(код): \(вывод)"
    case .невернаяКодировка(let аргументы):
      "Локальная команда git \(аргументы.joined(separator: " ")) вернула не-UTF-8."
    case .исполняемыйФайлНеНайден(let имя):
      "Не найден обязательный локальный исполняемый файл: \(имя)."
    case .кореньЧекаутаНеНайден:
      "Не найден корень текущего checkout с управляющими контрактами."
    case .неверныйОбъект:
      "Не удалось сериализовать JSON-объект фикстуры."
    }
  }
}

public enum ФикстурыУниверсальногоФоркИсполнителя {
  public static let имена = [
    "валидная",
    "валидная-цепочка",
    "валидная-другая-роль",
    "совпавшие-репозитории",
    "неверное-ядро",
    "локальный-коммит-в-зеркале",
    "расхождение-зеркала",
    "устаревшее-поколение",
    "паспорт-отсутствует",
    "паспорт-не-совпадает",
    "снимок-вне-основы",
    "чекаут-на-другом-снимке",
    "чекаут-вне-сборки",
    "submodule-как-писатель",
    "неверная-секция-сборки",
    "неизвестный-url-подмодуля",
    "несовпавшая-композиция",
    "несовпавшая-композиция-паспорта",
    "самоссылка",
    "прямой-цикл",
    "транзитивный-цикл",
    "транзитивный-возврат-к-ребёнку",
    "повторно-использованное-поддерево",
    "цикл-вложенных-репозиториев",
  ]

  public static func сФикстурой<Результат>(
    имя: String,
    _ действие: (ФикстураУниверсальногоФоркИсполнителя) throws -> Результат
  ) throws -> Результат {
    guard имена.contains(имя) else {
      throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.неизвестнаяФикстура(имя)
    }
    let корень = FileManager.default.temporaryDirectory.appendingPathComponent(
      "fum-универсальный-форк-исполнитель-\(UUID().uuidString)",
      isDirectory: true
    )
    try FileManager.default.createDirectory(at: корень, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: корень) }
    return try действие(try построить(имя: имя, корень: корень))
  }

  private static func построить(
    имя: String,
    корень: URL
  ) throws -> ФикстураУниверсальногоФоркИсполнителя {
    let исполняемыйФайлГит = try найтиИсполняемыйФайлГит()
    let репозиторийЯдра = корень.appendingPathComponent("ядро.git", isDirectory: true)
    let репозиторийИсполнителя = корень.appendingPathComponent(
      "исполнитель.git",
      isDirectory: true
    )
    let репозиторийСборки = корень.appendingPathComponent("сборка.git", isDirectory: true)
    let репозиторийПосредника = корень.appendingPathComponent(
      "посредник.git",
      isDirectory: true
    )
    let репозиторийВложенныйА = корень.appendingPathComponent(
      "вложенный-а.git",
      isDirectory: true
    )
    let репозиторийВложенныйБ = корень.appendingPathComponent(
      "вложенный-б.git",
      isDirectory: true
    )
    let писательЯдра = корень.appendingPathComponent("писатель-ядра", isDirectory: true)
    let писательИсполнителя = корень.appendingPathComponent(
      "писатель-исполнителя",
      isDirectory: true
    )
    let писательСборки = корень.appendingPathComponent("писатель-сборки", isDirectory: true)

    try создатьПустойГолыйРепозиторий(
      репозиторийЯдра,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try клонировать(
      репозиторийЯдра,
      в: писательЯдра,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try настроитьАвтора(в: писательЯдра, исполняемыйФайлГит: исполняемыйФайлГит)
    try записать(
      Data("Самодостаточное ядро фикстуры.\n".utf8),
      в: писательЯдра.appendingPathComponent("Ядро.md")
    )
    try выполнитьГит(
      ["add", "Ядро.md"],
      в: писательЯдра,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try выполнитьГит(
      ["commit", "-m", "Опубликованное поколение ядра"],
      в: писательЯдра,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    let поколениеЯдра = try выводГит(
      ["rev-parse", "HEAD"],
      в: писательЯдра,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try выполнитьГит(
      ["push", "origin", "HEAD:refs/heads/master"],
      в: писательЯдра,
      исполняемыйФайлГит: исполняемыйФайлГит
    )

    try создатьПустойГолыйРепозиторий(
      репозиторийСборки,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try клонировать(
      репозиторийСборки,
      в: писательСборки,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try настроитьАвтора(в: писательСборки, исполняемыйФайлГит: исполняемыйФайлГит)
    try записать(
      Data("Сборка фикстуры.\n".utf8),
      в: писательСборки.appendingPathComponent("Сборка.md")
    )
    try выполнитьГит(
      ["add", "Сборка.md"],
      в: писательСборки,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try выполнитьГит(
      ["commit", "-m", "Основа сборки"],
      в: писательСборки,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    let основаСборки = try выводГит(
      ["rev-parse", "HEAD"],
      в: писательСборки,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try выполнитьГит(
      ["push", "origin", "HEAD:refs/heads/master"],
      в: писательСборки,
      исполняемыйФайлГит: исполняемыйФайлГит
    )

    var репозиторииПоИдентификатору: [String: URL] = [
      "репозиторий.ядро": репозиторийЯдра,
      "репозиторий.исполнитель": репозиторийИсполнителя,
      "репозиторий.сборка": репозиторийСборки,
    ]
    var объектПосредника: String?
    if имя == "транзитивный-цикл" {
      объектПосредника = try создатьПосредника(
        репозиторий: репозиторийПосредника,
        корень: корень,
        имяЦели: "сборка",
        адресЦели: "../сборка.git",
        объектЦели: основаСборки,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
      репозиторииПоИдентификатору["репозиторий.посредник"] = репозиторийПосредника
    }

    try выполнитьГит(
      ["clone", "--bare", репозиторийЯдра.path, репозиторийИсполнителя.path],
      в: корень,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try клонировать(
      репозиторийИсполнителя,
      в: писательИсполнителя,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try настроитьАвтора(
      в: писательИсполнителя,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try выполнитьГит(
      ["remote", "add", "upstream", репозиторийЯдра.path],
      в: писательИсполнителя,
      исполняемыйФайлГит: исполняемыйФайлГит
    )

    var объектВозвратногоПосредника: String?
    if [
      "транзитивный-возврат-к-ребёнку",
      "повторно-использованное-поддерево",
    ].contains(имя) {
      объектВозвратногоПосредника = try создатьПосредника(
        репозиторий: репозиторийПосредника,
        корень: корень,
        имяЦели: "исполнитель",
        адресЦели: "../исполнитель.git",
        объектЦели: поколениеЯдра,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
      репозиторииПоИдентификатору["репозиторий.посредник"] = репозиторийПосредника
    }
    var объектВложенногоА: String?
    if имя == "цикл-вложенных-репозиториев" {
      let основаВложенногоА = try создатьПростойРепозиторий(
        репозиторий: репозиторийВложенныйА,
        корень: корень,
        имя: "вложенный-а",
        исполняемыйФайлГит: исполняемыйФайлГит
      )
      let объектВложенногоБ = try создатьПосредника(
        репозиторий: репозиторийВложенныйБ,
        корень: корень,
        имяЦели: "вложенный-а",
        адресЦели: "../вложенный-а.git",
        объектЦели: основаВложенногоА,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
      объектВложенногоА = try дополнитьРепозиторийПодмодулем(
        репозиторий: репозиторийВложенныйА,
        корень: корень,
        имя: "вложенный-б",
        адрес: "../вложенный-б.git",
        объект: объектВложенногоБ,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
      репозиторииПоИдентификатору["репозиторий.вложенный-а"] = репозиторийВложенныйА
      репозиторииПоИдентификатору["репозиторий.вложенный-б"] = репозиторийВложенныйБ
    }

    let другаяРоль = имя == "валидная-другая-роль"
    let идентификаторРоли = другаяРоль ? "роль.проверяющий" : "роль.писатель"
    let поколениеНазначения = другаяРоль ? "назначение.2" : "назначение.1"
    let рабочаяСсылка =
      другаяРоль
      ? "refs/heads/роль/проверяющий"
      : "refs/heads/роль/писатель"
    if имя == "снимок-вне-основы" {
      try выполнитьГит(
        ["switch", "--orphan", String(рабочаяСсылка.dropFirst("refs/heads/".count))],
        в: писательИсполнителя,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    } else {
      try выполнитьГит(
        ["switch", "-c", String(рабочаяСсылка.dropFirst("refs/heads/".count))],
        в: писательИсполнителя,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    }

    let полномочия: [String: Any] = [
      "уровень_доступа": "публичный",
      "внешние_эффекты": [],
      "дальнейшая_делегация": false,
      "разрешённые_цели_запроса_слияния": [
        [
          "идентификатор_репозитория": "репозиторий.ядро",
          "целевая_ссылка": "refs/heads/master",
        ]
      ],
    ]
    let данныеПолномочий = try сериализовать(полномочия)
    let хэшПолномочий = хэш(данныеПолномочий)
    let путьПаспорта = "Паспорт-универсального-исполнителя.json"
    let паспорт: [String: Any] = [
      "поколение_схемы": 2,
      "идентификатор_паспорта": "паспорт.универсальный.1",
      "идентификатор_ребёнка": "подузел.универсальный",
      "идентификатор_репозитория": "репозиторий.исполнитель",
      "идентификатор_ядра": "репозиторий.ядро",
      "идентификатор_композиции": [
        "несовпавшая-композиция",
        "несовпавшая-композиция-паспорта",
      ].contains(имя)
        ? "композиция.другая" : "композиция.универсальная.1",
      "поколение_назначения": поколениеНазначения,
      "универсальный_профиль": [
        "идентификатор": "профиль.универсальный",
        "версия": 1,
        "способности": ["выполнение_шага", "проверка_репозитория"],
      ],
      "контекстная_роль": [
        "идентификатор": идентификаторРоли,
        "версия": 1,
      ],
      "полномочия": полномочия,
      "репозиторная_плоскость": [
        "зеркальная_ссылка": "refs/heads/master",
        "рабочая_ссылка": рабочаяСсылка,
        "ролевые_ссылки": [рабочаяСсылка],
        "поколение_ядра": поколениеЯдра,
      ],
      "управляющая_плоскость": [
        "пространство_очереди": "refs/fum/worktree-task-queues",
        "пространство_квитанций_продолжения":
          "refs/fum/квитанции-связанных-коммитов",
        "путь_очереди":
          "Инструменты/fum-ocheredj-zadach-git-vetki/scripts/ocheredj-zadach-git-vetki.py",
        "путь_селектора":
          "Инструменты/fum-sleduyusjhij-shag-vetki/scripts/branch-next-step.py",
        "путь_рабочего_набора":
          "Планирование/следующие-шаги-веток/исполнитель.md",
      ],
    ]
    let данныеПаспорта = try сериализовать(паспорт)

    try записатьДочерниеКонтракты(
      в: писательИсполнителя,
      паспорт: имя == "паспорт-отсутствует" ? nil : данныеПаспорта,
      рабочаяСсылка: рабочаяСсылка,
      конечнаяЦепочка: имя == "валидная-цепочка"
    )
    try выполнитьГит(
      ["add", "--all"],
      в: писательИсполнителя,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    switch имя {
    case "самоссылка":
      try добавитьПодмодульВИндекс(
        писатель: писательИсполнителя,
        имя: "сам",
        путь: "Вложенные/сам",
        адрес: "../исполнитель.git",
        объект: поколениеЯдра,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    case "прямой-цикл":
      try добавитьПодмодульВИндекс(
        писатель: писательИсполнителя,
        имя: "сборка",
        путь: "Вложенные/сборка",
        адрес: "../сборка.git",
        объект: основаСборки,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    case "транзитивный-цикл":
      guard let объектПосредника else {
        throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.неверныйОбъект
      }
      try добавитьПодмодульВИндекс(
        писатель: писательИсполнителя,
        имя: "посредник",
        путь: "Вложенные/посредник",
        адрес: "../посредник.git",
        объект: объектПосредника,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    case "транзитивный-возврат-к-ребёнку", "повторно-использованное-поддерево":
      guard let объектВозвратногоПосредника else {
        throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.неверныйОбъект
      }
      try добавитьПодмодульВИндекс(
        писатель: писательИсполнителя,
        имя: "возвратный-посредник",
        путь: "Вложенные/возвратный-посредник",
        адрес: "../посредник.git",
        объект: объектВозвратногоПосредника,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    case "цикл-вложенных-репозиториев":
      guard let объектВложенногоА else {
        throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.неверныйОбъект
      }
      try добавитьПодмодульВИндекс(
        писатель: писательИсполнителя,
        имя: "вложенный-а",
        путь: "Вложенные/вложенный-а",
        адрес: "../вложенный-а.git",
        объект: объектВложенногоА,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    case "неизвестный-url-подмодуля":
      try добавитьПодмодульВИндекс(
        писатель: писательИсполнителя,
        имя: "неизвестный",
        путь: "Вложенные/неизвестный",
        адрес: "../неизвестный.git",
        объект: поколениеЯдра,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    default:
      break
    }
    try выполнитьГит(
      ["commit", "-m", "Принятый снимок универсального исполнителя"],
      в: писательИсполнителя,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    let снимокИсполнителяОбъект = try выводГит(
      ["rev-parse", "HEAD"],
      в: писательИсполнителя,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try выполнитьГит(
      ["push", "-u", "origin", "HEAD:\(рабочаяСсылка)"],
      в: писательИсполнителя,
      исполняемыйФайлГит: исполняемыйФайлГит
    )

    switch имя {
    case "совпавшие-репозитории":
      try выполнитьГит(
        ["remote", "set-url", "upstream", репозиторийИсполнителя.path],
        в: писательИсполнителя,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    case "неверное-ядро":
      try выполнитьГит(
        ["remote", "set-url", "upstream", репозиторийСборки.path],
        в: писательИсполнителя,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    case "локальный-коммит-в-зеркале":
      try продвинутьЗеркало(
        репозиторийИсполнителя,
        корень: корень,
        сРасхождением: false,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    case "расхождение-зеркала":
      try продвинутьЗеркало(
        репозиторийИсполнителя,
        корень: корень,
        сРасхождением: true,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    default:

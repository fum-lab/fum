      в: репозиторий,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
  }

  private static func записать(_ данные: Data, в адрес: URL) throws {
    try FileManager.default.createDirectory(
      at: адрес.deletingLastPathComponent(),
      withIntermediateDirectories: true
    )
    try данные.write(to: адрес, options: .atomic)
  }

  private static func сериализовать(_ объект: [String: Any]) throws -> Data {
    guard JSONSerialization.isValidJSONObject(объект) else {
      throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.неверныйОбъект
    }
    return try JSONSerialization.data(
      withJSONObject: объект,
      options: [.sortedKeys, .withoutEscapingSlashes]
    )
  }

  private static func хэш(_ данные: Data) -> String {
    "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
  }

  private static func кореньТекущегоЧекаута() throws -> URL {
    var кандидат = URL(
      fileURLWithPath: FileManager.default.currentDirectoryPath,
      isDirectory: true
    ).standardizedFileURL
    while true {
      let имеетПравила = FileManager.default.fileExists(
        atPath: кандидат.appendingPathComponent("AGENTS.md").path
      )
      let имеетОчередь = FileManager.default.fileExists(
        atPath: кандидат.appendingPathComponent(
          "Инструменты/fum-ocheredj-zadach-git-vetki/SKILL.md"
        ).path
      )
      if имеетПравила && имеетОчередь {
        return кандидат
      }
      let родитель = кандидат.deletingLastPathComponent()
      guard родитель.path != кандидат.path else {
        throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.кореньЧекаутаНеНайден
      }
      кандидат = родитель
    }
  }

  @discardableResult
  private static func выполнитьГит(
    _ аргументы: [String],
    в каталог: URL,
    исполняемыйФайлГит: URL
  ) throws -> Data {
    let процесс = Process()
    процесс.executableURL = исполняемыйФайлГит
    процесс.arguments = аргументы
    процесс.currentDirectoryURL = каталог
    процесс.environment = чистоеОкружение(в: каталог)
    let вывод = Pipe()
    процесс.standardOutput = вывод
    процесс.standardError = вывод
    try процесс.run()
    try? вывод.fileHandleForWriting.close()
    let данные = вывод.fileHandleForReading.readDataToEndOfFile()
    процесс.waitUntilExit()
    try? вывод.fileHandleForReading.close()
    guard процесс.terminationReason == .exit, процесс.terminationStatus == 0 else {
      let текст = String(data: данные, encoding: .utf8) ?? "<не-UTF-8>"
      throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.командаЗавершиласьНеудачно(
        аргументы,
        процесс.terminationStatus,
        текст.trimmingCharacters(in: .whitespacesAndNewlines)
      )
    }
    return данные
  }

  private static func выводГит(
    _ аргументы: [String],
    в каталог: URL,
    исполняемыйФайлГит: URL
  ) throws -> String {
    let данные = try выполнитьГит(
      аргументы,
      в: каталог,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    guard let вывод = String(data: данные, encoding: .utf8) else {
      throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.невернаяКодировка(аргументы)
    }
    return вывод.trimmingCharacters(in: .whitespacesAndNewlines)
  }

  private static func найтиИсполняемыйФайлГит() throws -> URL {
    let путь = ProcessInfo.processInfo.environment["PATH"] ?? ""
    for каталог in путь.split(separator: ":") where !каталог.isEmpty {
      let кандидат = URL(fileURLWithPath: String(каталог), isDirectory: true)
        .appendingPathComponent("git")
      if FileManager.default.isExecutableFile(atPath: кандидат.path) {
        return кандидат
      }
    }
    throw ОшибкаФикстурыУниверсальногоФоркИсполнителя.исполняемыйФайлНеНайден("git")
  }

  private static func чистоеОкружение(в каталог: URL) -> [String: String] {
    var окружение = ProcessInfo.processInfo.environment.filter { ключ, _ in
      !ключ.hasPrefix("GIT_")
    }
    окружение["GIT_CONFIG_NOSYSTEM"] = "1"
    окружение["GIT_CONFIG_GLOBAL"] =
      каталог.appendingPathComponent(
        "fum-отсутствующий-глобальный-gitconfig"
      ).path
    окружение["GIT_TERMINAL_PROMPT"] = "0"
    окружение["GIT_AUTHOR_DATE"] = "2001-01-01T00:00:00Z"
    окружение["GIT_COMMITTER_DATE"] = "2001-01-01T00:00:00Z"
    окружение["LC_ALL"] = "C"
    return окружение
  }

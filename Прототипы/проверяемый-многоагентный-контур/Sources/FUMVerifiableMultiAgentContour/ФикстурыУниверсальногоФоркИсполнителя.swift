    }

    let путьПодмодуля = "Исполнители/универсальный"
    let зарегистрированныйПутьПодмодуля =
      имя == "неверная-секция-сборки"
      ? "Исполнители/другой" : путьПодмодуля
    let предварительнаяСекцияСборки: String

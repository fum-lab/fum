  private static func продвинутьЗеркало(
    _ репозиторий: URL,
    корень: URL,
    сРасхождением: Bool,
    исполняемыйФайлГит: URL
  ) throws {
    let писатель = корень.appendingPathComponent(
      сРасхождением ? "писатель-расхождения" : "писатель-зеркала",
      isDirectory: true
    )
    if сРасхождением {
      try выполнитьГит(
        ["init", "--initial-branch=расхождение", писатель.path],
        в: корень,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
      try настроитьАвтора(в: писатель, исполняемыйФайлГит: исполняемыйФайлГит)
      try выполнитьГит(
        ["remote", "add", "origin", репозиторий.path],
        в: писатель,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
    } else {
      try клонировать(
        репозиторий,
        в: писатель,
        исполняемыйФайлГит: исполняемыйФайлГит
      )
      try настроитьАвтора(в: писатель, исполняемыйФайлГит: исполняемыйФайлГит)
    }
    try записать(
      Data((сРасхождением ? "Расхождение.\n" : "Локальный коммит.\n").utf8),
      в: писатель.appendingPathComponent("Зеркало.md")
    )
    try выполнитьГит(
      ["add", "Зеркало.md"],
      в: писатель,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    try выполнитьГит(
      ["commit", "-m", сРасхождением ? "Расхождение зеркала" : "Локальное продолжение зеркала"],
      в: писатель,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
    var аргументы = ["push"]
    if сРасхождением { аргументы.append("--force") }
    аргументы += ["origin", "HEAD:refs/heads/master"]
    try выполнитьГит(
      аргументы,
      в: писатель,
      исполняемыйФайлГит: исполняемыйФайлГит
    )
  }

  private static func создатьПустойГолыйРепозиторий(
    _ репозиторий: URL,
    исполняемыйФайлГит: URL
  ) throws {
    try выполнитьГит(
      ["init", "--bare", "--initial-branch=master", репозиторий.path],
      в: репозиторий.deletingLastPathComponent(),
      исполняемыйФайлГит: исполняемыйФайлГит
    )
  }

  private static func клонировать(
    _ репозиторий: URL,
    в чекаут: URL,
    безЧекаута: Bool = false,
    исполняемыйФайлГит: URL
  ) throws {
    var аргументы = ["clone"]
    if безЧекаута { аргументы.append("--no-checkout") }
    аргументы += [репозиторий.path, чекаут.path]
    try выполнитьГит(
      аргументы,
      в: чекаут.deletingLastPathComponent(),
      исполняемыйФайлГит: исполняемыйФайлГит
    )
  }


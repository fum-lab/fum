  private func сохранитьОтвет(
    поколение: String,
    сторона: СторонаВетвевогоФорка,
    задача: String,
    среда: String
  ) throws {
    guard !задача.isEmpty, !среда.isEmpty else {
      try сделатьПопыткуНеизвестной(
        поколение: поколение,
        сторона: сторона,
        видимыеСвязи: [ВидимаяСвязьСозданнойЗадачи(задача: задача, среда: среда)]
      )
      throw ОшибкаКорневогоРеестраЗапусков("неполный_ответ_среды")
    }
    let код = try изменитьСРезультатом { состояние -> String? in
      guard var поколениеЗапись = состояние.поколения[поколение],
        var ветвь = поколениеЗапись.ветви[сторона.rawValue],
        поколениеЗапись.фаза == .подготовка,
        ветвь.попытка.состояние == .вызовНачат || ветвь.попытка.состояние == .неизвестна
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неверная_фаза_ответа")
      }
      let ограждение =
        "\(поколение)/\(сторона.rawValue)/\(ветвь.шаг)/\(ветвь.попытка.идентификатор)/\(ветвь.попытка.хэшКонверта)/\(задача)/\(среда)"
      let предварительноеОграждение =
        "\(поколение)/\(сторона.rawValue)/\(ветвь.шаг)/\(ветвь.попытка.идентификатор)/\(ветвь.попытка.хэшКонверта)/неизвестно"
      if let прежнее = состояние.задачиСреды[задача],
        прежнее != ограждение,
        прежнее != предварительноеОграждение
      {
        ветвь.попытка.состояние = .неизвестна
        ветвь.попытка.идентификаторЗадачи = задача
        ветвь.попытка.идентификаторСреды = среда
        зарезервироватьНеоднозначнуюСвязь(
          состояние: &состояние,
          ограждение: предварительноеОграждение,
          задача: nil,
          среда: среда
        )
        поколениеЗапись.ветви[сторона.rawValue] = ветвь
        состояние.поколения[поколение] = поколениеЗапись
        _ = try синхронизироватьРесурснуюПопыткуСреды(
          состояние: &состояние,
          ветвь: ветвь,
          исходНеизвестен: true
        )
        return "задача_среды_уже_связана"
      }
      if let прежнее = состояние.средыЗадач[среда],
        прежнее != ограждение,
        прежнее != предварительноеОграждение
      {
        ветвь.попытка.состояние = .неизвестна
        ветвь.попытка.идентификаторЗадачи = задача
        ветвь.попытка.идентификаторСреды = среда
        зарезервироватьНеоднозначнуюСвязь(
          состояние: &состояние,
          ограждение: предварительноеОграждение,
          задача: задача,
          среда: nil
        )
        поколениеЗапись.ветви[сторона.rawValue] = ветвь
        состояние.поколения[поколение] = поколениеЗапись
        _ = try синхронизироватьРесурснуюПопыткуСреды(
          состояние: &состояние,
          ветвь: ветвь,
          исходНеизвестен: true
        )
        return "среда_задачи_уже_связана"
      }
      состояние.задачиСреды[задача] = ограждение
      состояние.средыЗадач[среда] = ограждение
      ветвь.попытка.идентификаторЗадачи = задача
      ветвь.попытка.идентификаторСреды = среда
      ветвь.попытка.состояние = .ответПодтверждён
      поколениеЗапись.ветви[сторона.rawValue] = ветвь
      состояние.поколения[поколение] = поколениеЗапись
      let освобожденаЁмкость = try синхронизироватьРесурснуюПопыткуСреды(
        состояние: &состояние,
        ветвь: ветвь,
        исходНеизвестен: false
      )
      if освобожденаЁмкость {
        _ = try допуститьОжидающиеРесурсныеПопытки(&состояние)
      }
      return nil
    }
    if let код { throw ОшибкаКорневогоРеестраЗапусков(код) }
  }

  private func сделатьПопыткуНеизвестной(

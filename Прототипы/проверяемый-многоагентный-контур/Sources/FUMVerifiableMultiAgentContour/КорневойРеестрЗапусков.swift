private func связатьРесурсныйДопускСКорневойВетвью(
  попытка: ЗаписьРесурснойПопытки,
  назначение: ЗаписьРесурсногоНазначения,
  состояние: inout СостояниеКорневогоРеестраЗапусков
) throws {
  let спецификация = назначение.спецификация
  guard var поколение = состояние.поколения[спецификация.поколение] else {
    return
  }
  guard поколение.фаза == .подготовка,
    var ветвь = поколение.ветви[спецификация.сторона.rawValue],
    ветвь.назначение == спецификация.корневоеНазначение,
    ветвь.попытка.идентификатор == спецификация.корневаяПопытка,
    ветвь.попытка.состояние == .подготовлена,
    ветвь.попытка.числоВызовов == 0,
    ветвь.идентификаторОбщегоКаталога == спецификация.общийКаталог,
    let хэшДопуска = попытка.хэшДопуска
  else {
    throw ОшибкаКорневогоРеестраЗапусков("несовпавшее_корневое_назначение")
  }
  let существующийКортеж = [
    ветвь.попытка.идентификаторРесурсногоНазначения,
    ветвь.попытка.хэшРесурсногоНазначения,
    ветвь.попытка.идентификаторРесурснойПопытки,
    ветвь.попытка.хэшРесурсногоДопуска,
  ]
  if существующийКортеж.contains(where: { $0 != nil }) {
    guard ветвь.попытка.идентификаторРесурсногоНазначения == попытка.назначение,
      ветвь.попытка.хэшРесурсногоНазначения == попытка.хэшНазначения,
      ветвь.попытка.идентификаторРесурснойПопытки == попытка.идентификатор,
      ветвь.попытка.хэшРесурсногоДопуска == хэшДопуска
    else {
      throw ОшибкаКорневогоРеестраЗапусков("ветвь_уже_связана_с_иным_ресурсным_допуском")
    }
    return
  }
  ветвь.попытка.идентификаторРесурсногоНазначения = попытка.назначение
  ветвь.попытка.хэшРесурсногоНазначения = попытка.хэшНазначения
  ветвь.попытка.идентификаторРесурснойПопытки = попытка.идентификатор
  ветвь.попытка.хэшРесурсногоДопуска = хэшДопуска
  ветвь.попытка.хэшКонверта = try сформироватьЗапросСоздания(
    поколение: поколение,
    ветвь: ветвь
  ).хэшКонверта
  поколение.ветви[спецификация.сторона.rawValue] = ветвь
  состояние.поколения[спецификация.поколение] = поколение
}


        )
      else {
        throw ОшибкаКорневогоРеестраЗапусков("превышен_предел_ресурсной_ёмкости")
      }
      попытка.состояние = активноеСостояние
      попытка.маска = полнаяМаска
      попытка.идентификаторЗадачи = свидетельство.идентификаторЗадачи
      попытка.идентификаторСреды = свидетельство.идентификаторСреды
      состояние.ресурсныеПопытки[попытка.идентификатор] = попытка
      return try решениеРесурсногоРаспределения(попытка, состояние: состояние)
    }
  }


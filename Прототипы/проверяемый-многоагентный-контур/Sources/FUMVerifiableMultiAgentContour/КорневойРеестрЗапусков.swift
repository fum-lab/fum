public final class КорневойРеестрЗапусков {
  private let каталог: URL
  private var адресСостояния: URL { каталог.appendingPathComponent("реестр.json") }
  private var адресБлокировки: URL { каталог.appendingPathComponent("блокировка") }

  public init(каталог: URL) throws {
    self.каталог = каталог.standardizedFileURL
    try ХранениеКорневогоРеестра.обеспечитьКаталог(self.каталог)
    try сБлокировкой { _ in
      if !ХранениеКорневогоРеестра.существует(адресСостояния) {
        try сохранить(.пустое)
      } else {
        _ = try прочитать()
      }
    }
  }

  public func подготовитьПоколение(
    _ спецификация: СпецификацияПоколенияКорневогоЗапуска
  ) throws {
    try изменить { состояние in
      guard состояние.поколения[спецификация.идентификатор] == nil else {
        throw ОшибкаКорневогоРеестраЗапусков("поколение_уже_существует")
      }
      guard спецификация.ветви.count == 2,
        Set(спецификация.ветви.map(\.сторона)) == Set(стороныВетвевогоФорка),
        проверитьВершину(спецификация.исходнаяВершина)
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неверная_спецификация_поколения")
      }
      guard спецификация.идентичностьКонтроллера == .недоступна,
        спецификация.идентификаторКонтроллера == nil
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неподдержанная_идентичность_контроллера")
      }

      var ветви: [String: ЗаписьВетвиКорневогоЗапуска] = [:]
      var локальныеПары = Set<String>()
      var локальныеКопии = Set<String>()
      var локальныеФорки = Set<String>()
      var локальныеПопытки = Set<String>()
      var локальныеИсточники = Set<String>()
      var локальныеФизическиеКопии = Set<String>()
      for ветвь in спецификация.ветви {
        let пара = ключРабочейПары(ветвь.идентификаторРепозитория, ветвь.рабочаяСсылка)
        let физическийИсточник = try идентичностьФизическогоИсточника(ветвь.адресИсточника)
        let каноническийИсточник = каноническийПуть(ветвь.адресИсточника)
        let физическаяКопия = try идентичностьЦелевойРабочейКопии(ветвь.адресРабочейКопии)
        guard ветвь.рабочаяСсылка.hasPrefix("refs/heads/"),
          [
            спецификация.идентификатор,
            ветвь.идентификаторНазначения,
            ветвь.роль,
            ветвь.идентификаторРебёнка,
            ветвь.идентификаторФорка,
            ветвь.идентификаторРепозитория,
            ветвь.идентификаторРабочейКопии,
            ветвь.идентификаторПопытки,
            ветвь.идентификаторШага,
            ветвь.идентификаторПроекта,
          ].allSatisfy(проверитьНепустоеОграждение),
          локальныеПары.insert(пара).inserted,
          локальныеКопии.insert(ветвь.идентификаторРабочейКопии).inserted,
          локальныеФорки.insert(ветвь.идентификаторФорка).inserted,
          локальныеПопытки.insert(ветвь.идентификаторПопытки).inserted,
          локальныеИсточники.insert(каноническийИсточник.path).inserted,
          локальныеФизическиеКопии.insert(физическаяКопия).inserted
        else {
          throw ОшибкаКорневогоРеестраЗапусков("дублированная_ветвь_поколения")
        }
        guard состояние.рабочиеПары[пара] == nil else {
          throw ОшибкаКорневогоРеестраЗапусков("рабочая_пара_уже_зарезервирована")
        }
        guard состояние.рабочиеКопии[ветвь.идентификаторРабочейКопии] == nil else {
          throw ОшибкаКорневогоРеестраЗапусков("рабочая_копия_уже_зарезервирована")
        }
        guard состояние.форки[ветвь.идентификаторФорка] == nil else {
          throw ОшибкаКорневогоРеестраЗапусков("форк_уже_зарезервирован")
        }
        guard состояние.попытки[ветвь.идентификаторПопытки] == nil else {
          throw ОшибкаКорневогоРеестраЗапусков("попытка_уже_зарезервирована")
        }
        guard состояние.физическиеРабочиеКопии[физическаяКопия] == nil else {
          throw ОшибкаКорневогоРеестраЗапусков("физическая_рабочая_копия_уже_зарезервирована")
        }
        guard состояние.физическиеИсточники[физическийИсточник] == nil else {
          throw ОшибкаКорневогоРеестраЗапусков("физический_источник_уже_зарезервирован")
        }
        let ограждение = "\(спецификация.идентификатор)/\(ветвь.сторона.rawValue)"
        состояние.рабочиеПары[пара] = ветвь.идентификаторФорка
        состояние.рабочиеКопии[ветвь.идентификаторРабочейКопии] = ветвь.идентификаторФорка
        состояние.форки[ветвь.идентификаторФорка] = ограждение

    guard let запись = состояние.поколения[поколение],
      let ветвь = запись.ветви[сторона.rawValue]
    else { return false }
    return запись.фаза == .активация
      && запись.хэшКвитанции == хэшКвитанции
      && ветвь.попытка.состояние == .подтверждена
      && ветвь.попытка.числоВызовов == 1
      && ветвь.попытка.подтверждённыйСеанс == идентификаторЗадачи
  }


        идентификаторЗадачи: задача,
        идентификаторСреды: среда,
        подтверждённыйСеанс: сеанс,
        состояниеПопытки: ветвь.попытка.состояние.rawValue,
        числоВызовов: ветвь.попытка.числоВызовов,

        назначение.спецификация.общийКаталог == свидетельство.общийКаталог,
        назначение.спецификация.классСессии != .внешнийПроверяющий,
        let поколение = состояние.поколения[свидетельство.поколение],
        поколение.фаза == .активация,
        поколение.исходнаяВершина == свидетельство.исходнаяВершина,
        let ветвь = поколение.ветви[свидетельство.сторона.rawValue],
        ветвь.назначение == назначение.спецификация.корневоеНазначение,
        ветвь.попытка.идентификатор == свидетельство.корневаяПопытка,
        ветвь.попытка.идентификаторРесурсногоНазначения == свидетельство.назначение,
        ветвь.попытка.хэшРесурсногоНазначения == свидетельство.хэшНазначения,
        ветвь.попытка.идентификаторРесурснойПопытки == свидетельство.попытка,
        ветвь.попытка.хэшРесурсногоДопуска == свидетельство.хэшДопуска,
        ветвь.попытка.идентификаторЗадачи == свидетельство.идентификаторЗадачи,
        ветвь.попытка.идентификаторСреды == свидетельство.идентификаторСреды,
        ветвь.попытка.подтверждённыйСеанс == свидетельство.идентификаторЗадачи
      else {
        throw ОшибкаКорневогоРеестраЗапусков(
          "несовпавшее_свидетельство_дочернего_захвата"
        )
      }
      let активноеСостояние: СостояниеРесурснойСессии =
        назначение.спецификация.классСессии == .писатель
        ? .активныйПисатель : .активныйМодератор
      if попытка.состояние == активноеСостояние {
        guard попытка.идентификаторЗадачи == свидетельство.идентификаторЗадачи,
          попытка.идентификаторСреды == свидетельство.идентификаторСреды
        else {
          throw ОшибкаКорневогоРеестраЗапусков(
            "несовпавшее_свидетельство_дочернего_захвата"
          )
        }
        return try решениеРесурсногоРаспределения(попытка, состояние: состояние)
      }
      guard [.неактивныйРебёнок, .ожидаетПродолжение].contains(попытка.состояние),

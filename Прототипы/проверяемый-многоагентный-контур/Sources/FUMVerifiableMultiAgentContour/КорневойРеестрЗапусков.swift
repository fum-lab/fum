  public func материализоватьИПроверитьКлон(
    поколение: String,
    сторона: СторонаВетвевогоФорка
  ) throws {
    let ветвь = try прочитатьВетвь(поколение: поколение, сторона: сторона)
    let адрес = URL(fileURLWithPath: ветвь.локальныйПуть, isDirectory: true)
    guard !ХранениеКорневогоРеестра.существует(адрес) else {
      throw ОшибкаКорневогоРеестраЗапусков("целевая_рабочая_копия_уже_существует")
    }
    _ = try командаГит(
      ["clone", "--no-checkout", "--no-local", ветвь.источник, адрес.path],
      корень: адрес.deletingLastPathComponent()
    )
    let поколениеЗапись = try прочитатьПоколение(поколение)
    let краткаяСсылка = String(ветвь.ссылка.dropFirst("refs/heads/".count))
    _ = try командаГит(
      ["checkout", "--detach", поколениеЗапись.исходнаяВершина], корень: адрес)
    _ = try командаГит(
      ["switch", "-c", краткаяСсылка], корень: адрес)
    try проверитьИСвязатьРабочуюКопию(поколение: поколение, сторона: сторона)
  }

  func проверитьИСвязатьРабочуюКопию(
    поколение: String,
    сторона: СторонаВетвевогоФорка
  ) throws {
    try изменить { состояние in
      guard var поколениеЗапись = состояние.поколения[поколение],
        var текущая = поколениеЗапись.ветви[сторона.rawValue]
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неизвестная_ветвь")
      }
      guard поколениеЗапись.фаза == .подготовка,
        текущая.попытка.состояние == .подготовлена
      else {
        throw ОшибкаКорневогоРеестраЗапусков("рабочая_копия_уже_заморожена")
      }
      let проверка = try проверитьФактическуюРабочуюКопию(
        ветвь: текущая,
        поколение: поколениеЗапись
      )
      if let владелец = состояние.общиеКаталоги[проверка.общийКаталогГит],
        владелец != текущая.форк
      {
        throw ОшибкаКорневогоРеестраЗапусков("общий_каталог_гит_уже_зарезервирован")
      }
      состояние.общиеКаталоги[проверка.общийКаталогГит] = текущая.форк
      текущая.каталогГит = проверка.каталогГит
      текущая.общийКаталогГит = проверка.общийКаталогГит
      текущая.идентификаторОбщегоКаталога = проверка.идентификаторОбщегоКаталога
      if (текущая.ресурсныеПолномочия ?? []).isEmpty {
        текущая.попытка.хэшКонверта = try сформироватьЗапросСоздания(
          поколение: поколениеЗапись,
          ветвь: текущая
        ).хэшКонверта
      } else {
        // Ресурсный конверт возникает только после атомарного связывания допуска.
        текущая.попытка.хэшКонверта = ""
      }
      поколениеЗапись.ветви[сторона.rawValue] = текущая
      состояние.поколения[поколение] = поколениеЗапись
    }
  }


private func ресурсноеСостояниеСоответствуетМаске(
  _ попытка: ЗаписьРесурснойПопытки,
  назначение: СтруктурированноеРесурсноеНазначение
) -> Bool {
  let пустая = маскаРесурсногоВыделения(
    для: .завершена,
    класс: назначение.классСессии
  )
  let толькоКвоты = маскаРесурсногоВыделения(
    для: .неактивныйРебёнок,
    класс: назначение.классСессии
  )
  let полная = маскаРесурсногоВыделения(
    для: .зарезервирована,
    класс: назначение.классСессии
  )
  let идентификаторыСогласованы =
    (попытка.идентификаторЗадачи == nil) == (попытка.идентификаторСреды == nil)
  switch попытка.состояние {
  case .ожидаетРесурсы, .завершена:
    return попытка.маска == пустая
  case .зарезервирована:
    return назначение.классСессии != .внешнийПроверяющий
      && попытка.маска == полная
      && попытка.идентификаторЗадачи == nil
      && попытка.идентификаторСреды == nil
  case .неактивныйРебёнок, .ожидаетПродолжение:
    return назначение.классСессии != .внешнийПроверяющий
      && попытка.маска == толькоКвоты
      && идентификаторыСогласованы
  case .активныйПисатель:
    return назначение.классСессии == .писатель
      && попытка.маска == полная
      && попытка.идентификаторЗадачи != nil
      && идентификаторыСогласованы
  case .активныйМодератор:
    return назначение.классСессии == .модератор
      && попытка.маска == полная
      && попытка.идентификаторЗадачи != nil
      && идентификаторыСогласованы
  case .внешнийПроверяющийБезЗаписи:
    return назначение.классСессии == .внешнийПроверяющий
      && попытка.маска == толькоКвоты
      && идентификаторыСогласованы
  case .остановкаЗапрошена, .отменаЗапрошена, .внешнийИсходНеизвестен:
    if назначение.классСессии == .внешнийПроверяющий {
      return попытка.маска == толькоКвоты
    }
    if попытка.идентификаторЗадачи == nil || попытка.идентификаторСреды == nil {
      return попытка.маска == полная
    }
    return попытка.маска == полная || попытка.маска == толькоКвоты
  }
}

private func сформироватьРесурсныеСчётчики(
  _ состояние: СостояниеКорневогоРеестраЗапусков,
  ревизия: Int
) -> ОграждённыеСчётчикиРесурсногоРаспределения {
  var форки: [String: Int] = [:]
  var назначения: [String: Int] = [:]
  var дети: [String: Int] = [:]
  var среды: [String: Int] = [:]
  var модели: [String: Int] = [:]
  var состояния: [String: Int] = [:]
  for попытка in состояние.ресурсныеПопытки.values {
    увеличить(&состояния, попытка.состояние.rawValue)
    guard let назначение = состояние.ресурсныеНазначения[попытка.назначение]?.спецификация
    else { continue }
    if попытка.маска.форк { увеличить(&форки, назначение.форк) }
    if попытка.маска.назначение { увеличить(&назначения, назначение.идентификатор) }
    if попытка.маска.ребёнок { увеличить(&дети, назначение.ребёнок) }
    if попытка.маска.настольнаяСреда { увеличить(&среды, назначение.настольнаяСреда) }
    if попытка.маска.профильМодели { увеличить(&модели, назначение.профильМодели) }
  }
  return ОграждённыеСчётчикиРесурсногоРаспределения(
    ревизия: ревизия,
    владельцыФорков: форки,
    назначения: назначения,
    дети: дети,
    настольныеСреды: среды,
    профилиМоделей: модели,
    состояния: состояния
  )
}

private func ресурснаяЁмкостьДопускает(
  _ назначение: СтруктурированноеРесурсноеНазначение,
  маска: МаскаРесурсногоВыделения,
  состояние: СостояниеКорневогоРеестраЗапусков,
  исключая исключённаяПопытка: String? = nil
) -> Bool {
  let пределы = состояние.пределыРесурсногоРаспределения
  guard let пределФорка = пределы.форки[назначение.форк],
    let пределНазначения = пределы.назначения[назначение.идентификатор],
    let пределРебёнка = пределы.дети[назначение.ребёнок],
    let пределСреды = пределы.настольныеСреды[назначение.настольнаяСреда],
    let пределМодели = пределы.профилиМоделей[назначение.профильМодели]
  else { return false }
  var использованиеФорка = 0
  var использованиеНазначения = 0
  var использованиеРебёнка = 0
  var использованиеСреды = 0
  var использованиеМодели = 0
  for попытка in состояние.ресурсныеПопытки.values {
    guard попытка.идентификатор != исключённаяПопытка,
      let другое = состояние.ресурсныеНазначения[попытка.назначение]?.спецификация
    else { continue }
    if попытка.маска.форк && другое.форк == назначение.форк { использованиеФорка += 1 }
    if попытка.маска.назначение && другое.идентификатор == назначение.идентификатор {
      использованиеНазначения += 1
    }
    if попытка.маска.ребёнок && другое.ребёнок == назначение.ребёнок {
      использованиеРебёнка += 1
    }
    if попытка.маска.настольнаяСреда
      && другое.настольнаяСреда == назначение.настольнаяСреда
    {
      использованиеСреды += 1
    }
    if попытка.маска.профильМодели && другое.профильМодели == назначение.профильМодели {
      использованиеМодели += 1
    }
  }
  return (!маска.форк || использованиеФорка + 1 <= пределФорка)
    && (!маска.назначение || использованиеНазначения + 1 <= пределНазначения)
    && (!маска.ребёнок || использованиеРебёнка + 1 <= пределРебёнка)
    && (!маска.настольнаяСреда || использованиеСреды + 1 <= пределСреды)
    && (!маска.профильМодели || использованиеМодели + 1 <= пределМодели)
}

private func попыткиКонфликтуютДляПорядка(
  _ левая: СтруктурированноеРесурсноеНазначение,
  _ правая: СтруктурированноеРесурсноеНазначение,
  пределы: КаталогПределовРесурсногоРаспределения
) -> Bool {
  if ресурсныеНазначенияКонфликтуют(левая, правая) { return true }
  return (левая.форк == правая.форк && пределы.форки[левая.форк] == 1)
    || (левая.идентификатор == правая.идентификатор
      && пределы.назначения[левая.идентификатор] == 1)
    || (левая.ребёнок == правая.ребёнок && пределы.дети[левая.ребёнок] == 1)
    || (левая.настольнаяСреда == правая.настольнаяСреда
      && пределы.настольныеСреды[левая.настольнаяСреда] == 1)
    || (левая.профильМодели == правая.профильМодели
      && пределы.профилиМоделей[левая.профильМодели] == 1)
}

@discardableResult
private func допуститьОжидающиеРесурсныеПопытки(
  _ состояние: inout СостояниеКорневогоРеестраЗапусков
) throws -> [String] {
  let ожидающие = состояние.ресурсныеПопытки.values
    .filter { $0.состояние == .ожидаетРесурсы }
    .sorted { ($0.номер, $0.идентификатор) < ($1.номер, $1.идентификатор) }
  var оставленные: [ЗаписьРесурснойПопытки] = []
  var допущенные: [String] = []
  for кандидат in ожидающие {
    guard let назначениеКандидата = состояние.ресурсныеНазначения[кандидат.назначение]
    else {
      throw ОшибкаКорневогоРеестраЗапусков("неизвестное_ресурсное_назначение")
    }
    let спецификация = назначениеКандидата.спецификация
    let начальноеСостояние = начальноеСостояниеРесурснойСессии(
      спецификация.классСессии
    )
    let начальнаяМаска = маскаРесурсногоВыделения(
      для: начальноеСостояние,
      класс: спецификация.классСессии
    )
    let обойдётРаннего = оставленные.contains { ранняя in
      guard let раннееНазначение = состояние.ресурсныеНазначения[ранняя.назначение]
      else { return true }
      return попыткиКонфликтуютДляПорядка(
        раннееНазначение.спецификация,
        спецификация,
        пределы: состояние.пределыРесурсногоРаспределения
      )
    }
    let конфликтуетСВладельцем = состояние.ресурсныеПопытки.values.contains { владелец in
      guard владелец.идентификатор != кандидат.идентификатор,
        владелец.маска.изменяемыеРесурсы,
        let назначениеВладельца = состояние.ресурсныеНазначения[владелец.назначение]
      else { return false }
      return ресурсныеНазначенияКонфликтуют(
        назначениеВладельца.спецификация,
        спецификация
      )
    }
    guard !обойдётРаннего,
      !конфликтуетСВладельцем,
      ресурснаяЁмкостьДопускает(
        спецификация,
        маска: начальнаяМаска,
        состояние: состояние
      )
    else {
      оставленные.append(кандидат)
      continue
    }
    var допущенная = кандидат
    допущенная.состояние = начальноеСостояние
    допущенная.маска = начальнаяМаска
    допущенная.хэшДопуска = try хэшРесурсногоДопуска(
      попытка: допущенная,
      назначение: назначениеКандидата
    )
    try связатьРесурсныйДопускСКорневойВетвью(
      попытка: допущенная,
      назначение: назначениеКандидата,
      состояние: &состояние
    )
    состояние.ресурсныеПопытки[кандидат.идентификатор] = допущенная
    допущенные.append(кандидат.идентификатор)
  }
  return допущенные
}

private func проверитьРесурсноеСостояние(
  _ состояние: СостояниеКорневогоРеестраЗапусков
) throws {
  guard состояние.схема == 3,
    состояние.следующийНомерРесурснойПопытки >= 1,
    состояние.счётчикиРесурсногоРаспределения
      == сформироватьРесурсныеСчётчики(состояние, ревизия: состояние.ревизия)
  else {
    throw ОшибкаКорневогоРеестраЗапусков("повреждённое_ресурсное_состояние")
  }
  var ожидаемыеПределы = КаталогПределовРесурсногоРаспределения.пустой
  for (идентификатор, назначение) in состояние.ресурсныеНазначения {
    let спецификация = назначение.спецификация
    guard спецификация.идентификатор == идентификатор,
      try спецификация.каноническийХэш() == назначение.хэшНазначения,
      let пределФорка = спецификация.пределы.форк,
      let пределНазначения = спецификация.пределы.назначение,
      let пределРебёнка = спецификация.пределы.ребёнок,
      let пределСреды = спецификация.пределы.настольнаяСреда,
      let пределМодели = спецификация.пределы.профильМодели
    else {
      throw ОшибкаКорневогоРеестраЗапусков("повреждённое_ресурсное_назначение")
    }
    try зарегистрироватьПредел(
      &ожидаемыеПределы.форки, ключ: спецификация.форк, значение: пределФорка)
    try зарегистрироватьПредел(
      &ожидаемыеПределы.назначения,
      ключ: идентификатор,
      значение: пределНазначения
    )
    try зарегистрироватьПредел(
      &ожидаемыеПределы.дети, ключ: спецификация.ребёнок, значение: пределРебёнка)
    try зарегистрироватьПредел(
      &ожидаемыеПределы.настольныеСреды,
      ключ: спецификация.настольнаяСреда,
      значение: пределСреды
    )
    try зарегистрироватьПредел(
      &ожидаемыеПределы.профилиМоделей,
      ключ: спецификация.профильМодели,
      значение: пределМодели
    )
  }
  guard ожидаемыеПределы == состояние.пределыРесурсногоРаспределения else {
    throw ОшибкаКорневогоРеестраЗапусков("повреждённый_каталог_пределов")
  }
  for поколение in состояние.поколения.values {
    for ветвь in поколение.ветви.values {
      let кортеж = [
        ветвь.попытка.идентификаторРесурсногоНазначения,
        ветвь.попытка.хэшРесурсногоНазначения,
        ветвь.попытка.идентификаторРесурснойПопытки,
        ветвь.попытка.хэшРесурсногоДопуска,
      ]
      let числоПолей = кортеж.compactMap { $0 }.count
      let ресурсныеПолномочия = ветвь.ресурсныеПолномочия ?? []
      guard числоПолей == 0 || числоПолей == 4 else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённая_ресурсная_привязка_ветви")
      }
      guard !ресурсныеПолномочия.isEmpty || числоПолей == 0 else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённая_ресурсная_привязка_ветви")
      }
      if !ресурсныеПолномочия.isEmpty, числоПолей == 0 {
        guard ветвь.попытка.числоВызовов == 0,
          ветвь.попытка.хэшКонверта.isEmpty
        else {
          throw ОшибкаКорневогоРеестраЗапусков("повреждённая_ресурсная_привязка_ветви")
        }
      }
      guard числоПолей == 4 else { continue }
      guard
        let идентификаторНазначения =
          ветвь.попытка.идентификаторРесурсногоНазначения,
        let хэшНазначения = ветвь.попытка.хэшРесурсногоНазначения,
        let идентификаторПопытки = ветвь.попытка.идентификаторРесурснойПопытки,
        let хэшДопуска = ветвь.попытка.хэшРесурсногоДопуска,
        let назначение = состояние.ресурсныеНазначения[идентификаторНазначения],
        let попытка = состояние.ресурсныеПопытки[идентификаторПопытки],
        назначение.хэшНазначения == хэшНазначения,
        попытка.назначение == идентификаторНазначения,
        попытка.хэшНазначения == хэшНазначения,
        попытка.хэшДопуска == хэшДопуска,
        назначение.спецификация.поколение == поколение.идентификатор,
        назначение.спецификация.исходнаяВершина == поколение.исходнаяВершина,
        назначение.спецификация.сторона == ветвь.сторона,
        назначение.спецификация.корневоеНазначение == ветвь.назначение,
        назначение.спецификация.корневаяПопытка == ветвь.попытка.идентификатор,
        назначение.спецификация.форк == ветвь.форк,
        назначение.спецификация.ребёнок == ветвь.ребёнок,
        назначение.спецификация.репозиторий == ветвь.репозиторий,
        назначение.спецификация.рабочаяСсылка == ветвь.ссылка,
        назначение.спецификация.рабочаяКопия == ветвь.рабочаяКопия,
        назначение.спецификация.общийКаталог == ветвь.идентификаторОбщегоКаталога,
        ресурсныеПолномочия.contains(where: {
          $0.идентификатор == идентификаторНазначения
        }),
        попытка.идентификаторЗадачи == ветвь.попытка.идентификаторЗадачи,
        попытка.идентификаторСреды == ветвь.попытка.идентификаторСреды
      else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённая_ресурсная_привязка_ветви")
      }
      if ветвь.попытка.числоВызовов > 0, попытка.состояние == .завершена {
        guard let задача = попытка.идентификаторЗадачи,
          !задача.isEmpty,
          let среда = попытка.идентификаторСреды,
          !среда.isEmpty,
          ветвь.попытка.идентификаторЗадачи == задача,
          ветвь.попытка.идентификаторСреды == среда,
          let свидетельство = попытка.терминальноеСвидетельство,
          свидетельство.идентификаторЗадачи == задача,
          свидетельство.идентификаторСреды == среда
        else {
          throw ОшибкаКорневогоРеестраЗапусков("повреждённая_терминальная_квитанция")
        }
      }
    }
  }
  var номера = Set<Int>()
  for (идентификатор, попытка) in состояние.ресурсныеПопытки {
    guard попытка.идентификатор == идентификатор,
      попытка.номер > 0,
      попытка.номер < состояние.следующийНомерРесурснойПопытки,
      номера.insert(попытка.номер).inserted,
      let назначение = состояние.ресурсныеНазначения[попытка.назначение],
      попытка.хэшНазначения == назначение.хэшНазначения
    else {
      throw ОшибкаКорневогоРеестраЗапусков("повреждённая_ресурсная_попытка")
    }
    guard
      ресурсноеСостояниеСоответствуетМаске(
        попытка,
        назначение: назначение.спецификация
      )
    else {
      throw ОшибкаКорневогоРеестраЗапусков("повреждённая_маска_ресурсной_попытки")
    }
    if попытка.состояние == .ожидаетРесурсы {
      guard попытка.хэшДопуска == nil,
        попытка.маска
          == маскаРесурсногоВыделения(
            для: .ожидаетРесурсы,
            класс: назначение.спецификация.классСессии
          ),
        попытка.идентификаторЗадачи == nil,
        попытка.идентификаторСреды == nil,
        попытка.терминальноеСвидетельство == nil,
        попытка.хэшТерминальногоСвидетельства == nil,
        попытка.хэшТерминальнойКвитанции == nil,
        попытка.допущенныеПослеТерминализации == nil
      else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённая_ожидающая_попытка")
      }
    } else {
      guard let хэшДопуска = попытка.хэшДопуска,
        хэшДопуска == (try хэшРесурсногоДопуска(попытка: попытка, назначение: назначение))
      else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённый_ресурсный_допуск")
      }
      if попытка.состояние == .завершена {
        let пустаяМаска = маскаРесурсногоВыделения(
          для: .завершена,
          класс: назначение.спецификация.классСессии
        )
        guard попытка.маска == пустаяМаска,
          let свидетельство = попытка.терминальноеСвидетельство,
          свидетельство.назначение == попытка.назначение,
          свидетельство.хэшНазначения == попытка.хэшНазначения,
          свидетельство.поколение == назначение.спецификация.поколение,
          свидетельство.исходнаяВершина == назначение.спецификация.исходнаяВершина,
          свидетельство.сторона == назначение.спецификация.сторона,
          свидетельство.корневаяПопытка == назначение.спецификация.корневаяПопытка,
          свидетельство.репозиторий == назначение.спецификация.репозиторий,
          свидетельство.рабочаяСсылка == назначение.спецификация.рабочаяСсылка,
          свидетельство.рабочаяКопия == назначение.спецификация.рабочаяКопия,
          свидетельство.общийКаталог == назначение.спецификация.общийКаталог,
          свидетельство.попытка == попытка.идентификатор,
          свидетельство.хэшДопуска == попытка.хэшДопуска,
          попытка.идентификаторЗадачи == свидетельство.идентификаторЗадачи
            || (попытка.идентификаторЗадачи == nil
              && свидетельство.идентификаторЗадачи.isEmpty),
          попытка.идентификаторСреды == свидетельство.идентификаторСреды
            || (попытка.идентификаторСреды == nil
              && свидетельство.идентификаторСреды.isEmpty),
          проверитьВершину(свидетельство.конечнаяВершина),
          let хэшСвидетельства = попытка.хэшТерминальногоСвидетельства,
          хэшСвидетельства
            == ресурсныйХэш(try ресурсныеКаноническиеДанные(свидетельство)),
          let хэшКвитанции = попытка.хэшТерминальнойКвитанции,
          let допущенные = попытка.допущенныеПослеТерминализации,
          хэшКвитанции
            == ресурсныйХэш(
              try ресурсныеКаноническиеДанные(
                НагрузкаТерминальнойКвитанцииРесурсногоНазначения(
                  схема: "терминализация-ресурсного-назначения.2",
                  хэшСвидетельства: хэшСвидетельства,
                  допущенныеПопытки: допущенные
                )
              ))
        else {
          throw ОшибкаКорневогоРеестраЗапусков("повреждённая_терминальная_квитанция")
        }
      } else if попытка.терминальноеСвидетельство != nil
        || попытка.хэшТерминальногоСвидетельства != nil
        || попытка.хэшТерминальнойКвитанции != nil
        || попытка.допущенныеПослеТерминализации != nil
      {
        throw ОшибкаКорневогоРеестраЗапусков("преждевременная_терминальная_квитанция")
      }
    }
  }
  let владельцы = состояние.ресурсныеПопытки.values.filter {
    $0.маска.изменяемыеРесурсы
  }
  for (индекс, левый) in владельцы.enumerated() {
    guard let левоеНазначение = состояние.ресурсныеНазначения[левый.назначение] else {
      throw ОшибкаКорневогоРеестраЗапусков("неизвестное_ресурсное_назначение")
    }
    for правый in владельцы.dropFirst(индекс + 1) {
      guard let правоеНазначение = состояние.ресурсныеНазначения[правый.назначение],
        !ресурсныеНазначенияКонфликтуют(
          левоеНазначение.спецификация,
          правоеНазначение.спецификация
        )
      else {
        throw ОшибкаКорневогоРеестраЗапусков("конфликтующие_ресурсные_владельцы")
      }
    }
  }
  let счётчики = состояние.счётчикиРесурсногоРаспределения
  guard
    счётчики.владельцыФорков.allSatisfy({
      $0.value <= (состояние.пределыРесурсногоРаспределения.форки[$0.key] ?? -1)
    }),
    счётчики.назначения.allSatisfy({
      $0.value <= (состояние.пределыРесурсногоРаспределения.назначения[$0.key] ?? -1)
    }),
    счётчики.дети.allSatisfy({
      $0.value <= (состояние.пределыРесурсногоРаспределения.дети[$0.key] ?? -1)
    }),
    счётчики.настольныеСреды.allSatisfy({
      $0.value <= (состояние.пределыРесурсногоРаспределения.настольныеСреды[$0.key] ?? -1)
    }),
    счётчики.профилиМоделей.allSatisfy({
      $0.value <= (состояние.пределыРесурсногоРаспределения.профилиМоделей[$0.key] ?? -1)
    })
  else {
    throw ОшибкаКорневогоРеестраЗапусков("превышен_предел_ресурсной_ёмкости")
  }
}

private func сформироватьЗапросСоздания(
  поколение: ЗаписьПоколенияКорневогоЗапуска,
  ветвь: ЗаписьВетвиКорневогоЗапуска
) throws -> ЗапросСозданияЗадачи {
  guard let идентификаторОбщегоКаталога = ветвь.идентификаторОбщегоКаталога else {
    throw ОшибкаКорневогоРеестраЗапусков("непроверенная_рабочая_копия")
  }
  let ресурсныйКортеж = (
    ветвь.попытка.идентификаторРесурсногоНазначения,
    ветвь.попытка.хэшРесурсногоНазначения,
    ветвь.попытка.идентификаторРесурснойПопытки,
    ветвь.попытка.хэшРесурсногоДопуска
  )
  let ресурсныеПолномочия = ветвь.ресурсныеПолномочия ?? []
  let нагрузка = НагрузкаКонвертаСозданияЗадачи(
    поколение: поколение.идентификатор,
    исходнаяВершина: поколение.исходнаяВершина,
    сторона: ветвь.сторона,
    попытка: ветвь.попытка.идентификатор,
    назначение: ветвь.назначение,
    роль: ветвь.роль,
    ребёнок: ветвь.ребёнок,
    форк: ветвь.форк,
    репозиторий: ветвь.репозиторий,
    рабочаяСсылка: ветвь.ссылка,
    рабочаяКопия: ветвь.рабочаяКопия,
    идентификаторОбщегоКаталога: идентификаторОбщегоКаталога,
    шаг: ветвь.шаг,
    проект: ветвь.проект
  )
  let хэшКонверта: String
  switch ресурсныйКортеж {
  case (nil, nil, nil, nil):
    guard ресурсныеПолномочия.isEmpty else {
      throw ОшибкаКорневогоРеестраЗапусков("ресурсный_допуск_не_связан_с_host")
    }
    хэшКонверта = хэш(try каноническиеДанные(нагрузка))
  case (let идентификаторНазначения?, let хэшНазначения?, let ресурснаяПопытка?, let хэшДопуска?):
    guard !ресурсныеПолномочия.isEmpty,
      ресурсныеПолномочия.contains(where: {
        $0.идентификатор == идентификаторНазначения
      })
    else {
      throw ОшибкаКорневогоРеестраЗапусков("неожиданный_ресурсный_допуск_host")
    }
    let ресурснаяНагрузка = НагрузкаРесурсногоКонвертаСозданияЗадачи(
      схема: "корневой-конверт-создания-задачи.2",
      поколение: нагрузка.поколение,
      исходнаяВершина: нагрузка.исходнаяВершина,
      сторона: нагрузка.сторона,
      попытка: нагрузка.попытка,
      назначение: нагрузка.назначение,
      роль: нагрузка.роль,
      ребёнок: нагрузка.ребёнок,
      форк: нагрузка.форк,
      репозиторий: нагрузка.репозиторий,
      рабочаяСсылка: нагрузка.рабочаяСсылка,
      рабочаяКопия: нагрузка.рабочаяКопия,
      идентификаторОбщегоКаталога: нагрузка.идентификаторОбщегоКаталога,
      шаг: нагрузка.шаг,
      проект: нагрузка.проект,
      идентификаторРесурсногоНазначения: идентификаторНазначения,
      хэшРесурсногоНазначения: хэшНазначения,
      идентификаторРесурснойПопытки: ресурснаяПопытка,
      хэшРесурсногоДопуска: хэшДопуска
    )
    хэшКонверта = хэш(try каноническиеДанные(ресурснаяНагрузка))
  default:

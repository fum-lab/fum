  ) throws {
    try изменить { состояние in
      guard var поколениеЗапись = состояние.поколения[поколение],
        var ветвь = поколениеЗапись.ветви[сторона.rawValue]
      else { throw ОшибкаКорневогоРеестраЗапусков("неизвестная_ветвь") }
      guard поколениеЗапись.фаза == .подготовка else {
        throw ОшибкаКорневогоРеестраЗапусков("поколение_уже_заморожено")
      }
      guard
        ветвь.попытка.состояние == .вызовНачат
          || ветвь.попытка.состояние == .неизвестна
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неверная_фаза_неизвестной_попытки")
      }
      ветвь.попытка.состояние = .неизвестна
      let ограждение =
        "\(поколение)/\(сторона.rawValue)/\(ветвь.шаг)/\(ветвь.попытка.идентификатор)/\(ветвь.попытка.хэшКонверта)/неизвестно"
      for связь in видимыеСвязи {
        let задача = связь.задача.flatMap { $0.isEmpty ? nil : $0 }
        let среда = связь.среда.flatMap { $0.isEmpty ? nil : $0 }
        if ветвь.попытка.идентификаторЗадачи == nil { ветвь.попытка.идентификаторЗадачи = задача }
        if ветвь.попытка.идентификаторСреды == nil { ветвь.попытка.идентификаторСреды = среда }
        зарезервироватьНеоднозначнуюСвязь(
          состояние: &состояние,
          ограждение: ограждение,
          задача: задача,
          среда: среда
        )
      }
      поколениеЗапись.ветви[сторона.rawValue] = ветвь
      состояние.поколения[поколение] = поколениеЗапись
      _ = try синхронизироватьРесурснуюПопыткуСреды(
        состояние: &состояние,
        ветвь: ветвь,
        исходНеизвестен: true
      )
    }
  }

  private func синхронизироватьРесурснуюПопыткуСреды(
    состояние: inout СостояниеКорневогоРеестраЗапусков,
    ветвь: ЗаписьВетвиКорневогоЗапуска,
    исходНеизвестен: Bool
  ) throws -> Bool {
    let кортеж = [
      ветвь.попытка.идентификаторРесурсногоНазначения,
      ветвь.попытка.хэшРесурсногоНазначения,
      ветвь.попытка.идентификаторРесурснойПопытки,
      ветвь.попытка.хэшРесурсногоДопуска,
    ]
    let числоПолей = кортеж.compactMap { $0 }.count
    guard числоПолей == 0 || числоПолей == 4 else {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_ресурсная_привязка_host")
    }
    guard числоПолей == 4 else { return false }
    guard
      let идентификаторНазначения =
        ветвь.попытка.идентификаторРесурсногоНазначения,
      let хэшНазначения = ветвь.попытка.хэшРесурсногоНазначения,
      let идентификаторПопытки = ветвь.попытка.идентификаторРесурснойПопытки,
      let хэшДопуска = ветвь.попытка.хэшРесурсногоДопуска,
      let назначение = состояние.ресурсныеНазначения[идентификаторНазначения],
      var попытка = состояние.ресурсныеПопытки[идентификаторПопытки],
      назначение.хэшНазначения == хэшНазначения,
      попытка.назначение == идентификаторНазначения,
      попытка.хэшНазначения == хэшНазначения,
      попытка.хэшДопуска == хэшДопуска,
      попытка.состояние != .ожидаетРесурсы
    else {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_ресурсная_привязка_host")
    }
    if let существующаяЗадача = попытка.идентификаторЗадачи,
      let задача = ветвь.попытка.идентификаторЗадачи,
      существующаяЗадача != задача
    {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_ресурсная_привязка_host")
    }
    if let существующаяСреда = попытка.идентификаторСреды,
      let среда = ветвь.попытка.идентификаторСреды,
      существующаяСреда != среда
    {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_ресурсная_привязка_host")
    }
    if попытка.состояние == .завершена {
      guard попытка.идентификаторЗадачи == ветвь.попытка.идентификаторЗадачи,
        попытка.идентификаторСреды == ветвь.попытка.идентификаторСреды
      else {
        throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_ресурсная_привязка_host")
      }
      return false
    }
    if попытка.идентификаторЗадачи == nil {
      попытка.идентификаторЗадачи = ветвь.попытка.идентификаторЗадачи
    }
    if попытка.идентификаторСреды == nil {
      попытка.идентификаторСреды = ветвь.попытка.идентификаторСреды
    }
    let прежняяМаска = попытка.маска
    if исходНеизвестен {
      попытка.состояние = .внешнийИсходНеизвестен
    } else {
      guard ветвь.попытка.идентификаторЗадачи != nil,
        ветвь.попытка.идентификаторСреды != nil
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неполный_ответ_среды")
      }
      switch попытка.состояние {
      case .зарезервирована, .внешнийИсходНеизвестен:
        if назначение.спецификация.классСессии == .внешнийПроверяющий {
          попытка.состояние = .внешнийПроверяющийБезЗаписи
        } else {
          попытка.состояние = .неактивныйРебёнок
        }
        попытка.маска = маскаРесурсногоВыделения(
          для: попытка.состояние,
          класс: назначение.спецификация.классСессии
        )
      case .внешнийПроверяющийБезЗаписи, .неактивныйРебёнок,
        .ожидаетПродолжение, .активныйПисатель, .активныйМодератор,
        .остановкаЗапрошена, .отменаЗапрошена:
        break
      case .ожидаетРесурсы, .завершена:
        throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_ресурсная_привязка_host")
      }
    }
    состояние.ресурсныеПопытки[идентификаторПопытки] = попытка
    return маскаОсвобождаетРесурс(с: прежняяМаска, до: попытка.маска)
  }

  private func прочитатьВетвь(
    поколение: String,
    сторона: СторонаВетвевогоФорка
  ) throws -> ЗаписьВетвиКорневогоЗапуска {
    let поколениеЗапись = try прочитатьПоколение(поколение)
    guard let ветвь = поколениеЗапись.ветви[сторона.rawValue] else {
      throw ОшибкаКорневогоРеестраЗапусков("неизвестная_ветвь")
    }
    return ветвь
  }

  private func прочитатьПоколение(_ поколение: String) throws -> ЗаписьПоколенияКорневогоЗапуска {
    let состояние = try сБлокировкой { _ in try прочитать() }
    guard let запись = состояние.поколения[поколение] else {
      throw ОшибкаКорневогоРеестраЗапусков("неизвестное_поколение")
    }
    return запись
  }

  private func изменить(_ тело: (inout СостояниеКорневогоРеестраЗапусков) throws -> Void) throws {
    try сБлокировкой { _ in
      var состояние = try прочитать()
      try тело(&состояние)
      состояние.ревизия += 1
      состояние.счётчикиРесурсногоРаспределения = сформироватьРесурсныеСчётчики(
        состояние,
        ревизия: состояние.ревизия
      )
      try проверитьРесурсноеСостояние(состояние)
      try сохранить(состояние)
    }
  }

  private func изменитьСРезультатом<Результат>(
    _ тело: (inout СостояниеКорневогоРеестраЗапусков) throws -> Результат
  ) throws -> Результат {
    try сБлокировкой { _ in
      var состояние = try прочитать()
      let результат = try тело(&состояние)
      состояние.ревизия += 1
      состояние.счётчикиРесурсногоРаспределения = сформироватьРесурсныеСчётчики(
        состояние,
        ревизия: состояние.ревизия
      )
      try проверитьРесурсноеСостояние(состояние)
      try сохранить(состояние)
      return результат
    }
  }

  private func прочитать() throws -> СостояниеКорневогоРеестраЗапусков {
    let данные = try ХранениеКорневогоРеестра.прочитать(адресСостояния)
    let общийОбъект = try JSONSerialization.jsonObject(with: данные)
    guard let словарь = общийОбъект as? [String: Any],
      let схема = словарь["схема"] as? Int
    else { throw ОшибкаКорневогоРеестраЗапусков("повреждённый_реестр") }
    if схема == 2 {
      let прежнее = try JSONDecoder().decode(
        СостояниеКорневогоРеестраЗапусковВерсии2.self,
        from: данные
      )
      guard прежнее.ревизия >= 0,
        try каноническиеДанные(прежнее) == данные
      else { throw ОшибкаКорневогоРеестраЗапусков("повреждённый_реестр") }
      return прежнее.перенестиВТекущуюСхему()
    }
    let состояние = try JSONDecoder().decode(СостояниеКорневогоРеестраЗапусков.self, from: данные)
    guard состояние.схема == 3, состояние.ревизия >= 0,
      try каноническиеДанные(состояние) == данные
    else { throw ОшибкаКорневогоРеестраЗапусков("повреждённый_реестр") }
    try проверитьРесурсноеСостояние(состояние)
    try проверитьКорневуюСвязностьРесурсногоСостояния(состояние)
    return состояние
  }

  private func сохранить(_ состояние: СостояниеКорневогоРеестраЗапусков) throws {
    guard состояние.схема == 3 else {
      throw ОшибкаКорневогоРеестраЗапусков("неверная_схема_реестра")
    }
    try проверитьРесурсноеСостояние(состояние)
    try проверитьКорневуюСвязностьРесурсногоСостояния(состояние)
    try ХранениеКорневогоРеестра.сохранить(
      try каноническиеДанные(состояние),
      по: адресСостояния
    )
  }

  private func проверитьКорневуюСвязностьРесурсногоСостояния(
    _ состояние: СостояниеКорневогоРеестраЗапусков
  ) throws {
    guard !разрешитьСинтетическиеРесурсныеНазначения else { return }
    var попыткиПоКорневымВетвям: [String: String] = [:]
    for назначение in состояние.ресурсныеНазначения.values {
      let спецификация = назначение.спецификация
      guard let поколение = состояние.поколения[спецификация.поколение],
        поколение.исходнаяВершина == спецификация.исходнаяВершина,
        let ветвь = поколение.ветви[спецификация.сторона.rawValue],
        ветвь.назначение == спецификация.корневоеНазначение,
        ветвь.попытка.идентификатор == спецификация.корневаяПопытка,
        ветвь.роль == спецификация.роль,
        ветвь.ребёнок == спецификация.ребёнок,
        ветвь.форк == спецификация.форк,
        ветвь.репозиторий == спецификация.репозиторий,
        ветвь.ссылка == спецификация.рабочаяСсылка,
        ветвь.рабочаяКопия == спецификация.рабочаяКопия,
        ветвь.каталогГит != nil,
        ветвь.общийКаталогГит != nil,
        ветвь.идентификаторОбщегоКаталога == спецификация.общийКаталог,
        (ветвь.ресурсныеПолномочия ?? []).contains(where: {
          нормализованныеКорневыеПолномочия($0) == корневыеПолномочия(из: спецификация)
        })
      else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённая_корневая_связь_ресурсного_назначения")
      }
    }
    for попытка in состояние.ресурсныеПопытки.values {
      guard let назначение = состояние.ресурсныеНазначения[попытка.назначение] else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённая_корневая_связь_ресурсного_назначения")
      }
      let спецификация = назначение.спецификация
      guard let поколение = состояние.поколения[спецификация.поколение],
        let ветвь = поколение.ветви[спецификация.сторона.rawValue]
      else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённая_корневая_связь_ресурсной_попытки")
      }
      let кортеж = [
        ветвь.попытка.идентификаторРесурсногоНазначения,
        ветвь.попытка.хэшРесурсногоНазначения,
        ветвь.попытка.идентификаторРесурснойПопытки,
        ветвь.попытка.хэшРесурсногоДопуска,
      ]
      if попытка.состояние == .ожидаетРесурсы {
        guard кортеж.allSatisfy({ $0 == nil }) else {
          throw ОшибкаКорневогоРеестраЗапусков("повреждённая_корневая_связь_ресурсной_попытки")
        }
      } else {
        guard let хэшДопуска = попытка.хэшДопуска,
          ветвь.попытка.идентификаторРесурсногоНазначения == попытка.назначение,
          ветвь.попытка.хэшРесурсногоНазначения == попытка.хэшНазначения,
          ветвь.попытка.идентификаторРесурснойПопытки == попытка.идентификатор,
          ветвь.попытка.хэшРесурсногоДопуска == хэшДопуска,
          try сформироватьЗапросСоздания(поколение: поколение, ветвь: ветвь).хэшКонверта
            == ветвь.попытка.хэшКонверта
        else {
          throw ОшибкаКорневогоРеестраЗапусков("повреждённая_корневая_связь_ресурсной_попытки")
        }
      }
      let ключВетви = ключКорневойРесурснойВетви(назначение.спецификация)
      guard попыткиПоКорневымВетвям[ключВетви] == nil else {
        throw ОшибкаКорневогоРеестраЗапусков("повреждённая_корневая_связь_ресурсной_попытки")
      }
      попыткиПоКорневымВетвям[ключВетви] = попытка.идентификатор
    }
  }

  private func проверитьФактическуюРабочуюКопию(
    ветвь: ЗаписьВетвиКорневогоЗапуска,
    поколение: ЗаписьПоколенияКорневогоЗапуска
  ) throws -> ПровереннаяРабочаяКопия {
    let адрес = каноническийПуть(
      URL(fileURLWithPath: ветвь.локальныйПуть, isDirectory: true)
    )
    let фактическийКорень = каноническийПуть(
      URL(
        fileURLWithPath: try командаГит(["rev-parse", "--show-toplevel"], корень: адрес),
        isDirectory: true
      )
    )
    guard фактическийКорень.path == адрес.path,
      try командаГит(["rev-parse", "--is-inside-work-tree"], корень: адрес) == "true"
    else {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_физическая_рабочая_копия")
    }
    let физическаяРабочаяКопия = try идентичностьЦелевойРабочейКопии(адрес)
    guard физическаяРабочаяКопия == ветвь.физическаяРабочаяКопия else {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_физическая_рабочая_копия")
    }
    let фактическаяВершина = try командаГит(["rev-parse", "HEAD"], корень: адрес)
    let фактическаяСсылка = try командаГит(["symbolic-ref", "HEAD"], корень: адрес)
    let фактическийИсточник = try командаГит(["remote", "get-url", "origin"], корень: адрес)
    guard фактическаяВершина == поколение.исходнаяВершина else {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_исходная_вершина")
    }
    guard фактическаяСсылка == ветвь.ссылка else {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавшая_рабочая_ссылка")
    }
    let источник = каноническийПуть(
      URL(fileURLWithPath: фактическийИсточник, relativeTo: адрес)
    )
    let физическийИсточник = try идентичностьФизическогоИсточника(источник)
    guard физическийИсточник == ветвь.физическийИсточник else {
      throw ОшибкаКорневогоРеестраЗапусков("несовпавший_источник")
    }
    let каталогГит = try разрешитьПутьГит(
      try командаГит(["rev-parse", "--absolute-git-dir"], корень: адрес),
      относительно: адрес
    )
    let общийКаталогГит = try разрешитьПутьГит(
      try командаГит(["rev-parse", "--git-common-dir"], корень: адрес),
      относительно: адрес
    )
    guard каталогГит.path == общийКаталогГит.path else {
      throw ОшибкаКорневогоРеестраЗапусков("рабочая_копия_не_автономна")
    }
    return ПровереннаяРабочаяКопия(
      вершина: фактическаяВершина,
      ссылка: фактическаяСсылка,
      источник: источник.path,
      физическийИсточник: физическийИсточник,
      кореньРабочейКопии: адрес.path,
      физическаяРабочаяКопия: физическаяРабочаяКопия,
      каталогГит: каталогГит.path,
      общийКаталогГит: общийКаталогГит.path,
      идентификаторОбщегоКаталога: хэш(Data(общийКаталогГит.path.utf8))
    )
  }

  private func сБлокировкой<Результат>(_ тело: (БлокировкаКорневогоРеестра) throws -> Результат)
    throws -> Результат
  {
    let блокировка = try БлокировкаКорневогоРеестра(адрес: адресБлокировки)
    defer { блокировка.освободить() }
    return try тело(блокировка)
  }

  @discardableResult
  public func зарегистрироватьРесурсноеНазначение(
    _ спецификация: СтруктурированноеРесурсноеНазначение
  ) throws -> String {
    try проверитьСтруктурированноеРесурсноеНазначение(спецификация)
    let хэшНазначения = try спецификация.каноническийХэш()
    return try изменитьСРезультатом { состояние in
      if let существующее = состояние.ресурсныеНазначения[спецификация.идентификатор] {
        guard существующее.спецификация == спецификация,
          существующее.хэшНазначения == хэшНазначения
        else {
          throw ОшибкаКорневогоРеестраЗапусков("изменившееся_ресурсное_назначение")
        }
        return хэшНазначения
      }
      if !разрешитьСинтетическиеРесурсныеНазначения {
        guard let поколение = состояние.поколения[спецификация.поколение],
          let ветвь = поколение.ветви[спецификация.сторона.rawValue],
          поколение.исходнаяВершина == спецификация.исходнаяВершина,
          поколение.фаза == .подготовка,
          ветвь.назначение == спецификация.корневоеНазначение,
          ветвь.попытка.идентификатор == спецификация.корневаяПопытка,
          ветвь.роль == спецификация.роль,
          ветвь.ребёнок == спецификация.ребёнок,
          ветвь.форк == спецификация.форк,
          ветвь.репозиторий == спецификация.репозиторий,
          ветвь.ссылка == спецификация.рабочаяСсылка,
          ветвь.рабочаяКопия == спецификация.рабочаяКопия,
          ветвь.идентификаторОбщегоКаталога == спецификация.общийКаталог,
          ветвь.попытка.состояние == .подготовлена,
          ветвь.попытка.числоВызовов == 0
        else {
          throw ОшибкаКорневогоРеестраЗапусков("несовпавшее_корневое_назначение")
        }
        let ожидаемыеПолномочия = корневыеПолномочия(из: спецификация)
        guard
          (ветвь.ресурсныеПолномочия ?? []).contains(where: {
            нормализованныеКорневыеПолномочия($0) == ожидаемыеПолномочия
          })
        else {
          throw ОшибкаКорневогоРеестраЗапусков("несовпавшие_ресурсные_полномочия")
        }
      }
      guard let пределФорка = спецификация.пределы.форк,
        let пределНазначения = спецификация.пределы.назначение,
        let пределРебёнка = спецификация.пределы.ребёнок,
        let пределСреды = спецификация.пределы.настольнаяСреда,
        let пределМодели = спецификация.пределы.профильМодели
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неизвестный_предел_ёмкости")
      }
      try зарегистрироватьПредел(
        &состояние.пределыРесурсногоРаспределения.форки,
        ключ: спецификация.форк,
        значение: пределФорка
      )
      try зарегистрироватьПредел(
        &состояние.пределыРесурсногоРаспределения.назначения,
        ключ: спецификация.идентификатор,
        значение: пределНазначения
      )
      try зарегистрироватьПредел(
        &состояние.пределыРесурсногоРаспределения.дети,
        ключ: спецификация.ребёнок,
        значение: пределРебёнка
      )
      try зарегистрироватьПредел(
        &состояние.пределыРесурсногоРаспределения.настольныеСреды,
        ключ: спецификация.настольнаяСреда,
        значение: пределСреды
      )
      try зарегистрироватьПредел(
        &состояние.пределыРесурсногоРаспределения.профилиМоделей,
        ключ: спецификация.профильМодели,
        значение: пределМодели
      )
      состояние.ресурсныеНазначения[спецификация.идентификатор] =
        ЗаписьРесурсногоНазначения(
          спецификация: спецификация,
          хэшНазначения: хэшНазначения
        )
      return хэшНазначения
    }
  }

  public func запроситьРесурсныйДопуск(
    назначение: String,
    попытка: String,
    ожидаемыйХэшНазначения: String
  ) throws -> РешениеРесурсногоДопуска {
    guard проверитьНепустоеОграждение(попытка),
      проверитьРесурсныйХэш(ожидаемыйХэшНазначения)
    else {
      throw ОшибкаКорневогоРеестраЗапусков("неверная_ресурсная_попытка")
    }
    return try изменитьСРезультатом { состояние in
      guard let записьНазначения = состояние.ресурсныеНазначения[назначение],
        записьНазначения.хэшНазначения == ожидаемыйХэшНазначения
      else {
        throw ОшибкаКорневогоРеестраЗапусков("несовпавшее_ресурсное_назначение")
      }
      if let существующая = состояние.ресурсныеПопытки[попытка] {
        guard существующая.назначение == назначение,
          существующая.хэшНазначения == ожидаемыйХэшНазначения
        else {
          throw ОшибкаКорневогоРеестраЗапусков("попытка_связана_с_другим_назначением")
        }
        return try решениеРесурсногоРаспределения(
          существующая,
          состояние: состояние
        )
      }
      if !разрешитьСинтетическиеРесурсныеНазначения {
        let целеваяВетвь = ключКорневойРесурснойВетви(
          записьНазначения.спецификация
        )
        let имеетПрежнююПопытку = состояние.ресурсныеПопытки.values.contains { прежняяПопытка in
          guard
            let прежнееНазначение =
              состояние.ресурсныеНазначения[прежняяПопытка.назначение]
          else { return true }
          return ключКорневойРесурснойВетви(прежнееНазначение.спецификация)
            == целеваяВетвь
        }
        guard !имеетПрежнююПопытку else {
          throw ОшибкаКорневогоРеестраЗапусков("корневая_ветвь_уже_имеет_ресурсную_попытку")
        }
      }
      let номер = состояние.следующийНомерРесурснойПопытки
      guard номер > 0 && номер < Int.max else {
        throw ОшибкаКорневогоРеестраЗапусков("исчерпан_номер_ресурсной_попытки")
      }
      состояние.следующийНомерРесурснойПопытки += 1
      состояние.ресурсныеПопытки[попытка] = ЗаписьРесурснойПопытки(
        идентификатор: попытка,
        назначение: назначение,
        хэшНазначения: ожидаемыйХэшНазначения,
        номер: номер,
        состояние: .ожидаетРесурсы,
        маска: маскаРесурсногоВыделения(
          для: .ожидаетРесурсы, класс: записьНазначения.спецификация.классСессии),
        хэшДопуска: nil,
        идентификаторЗадачи: nil,
        идентификаторСреды: nil,
        терминальноеСвидетельство: nil,
        хэшТерминальногоСвидетельства: nil,
        хэшТерминальнойКвитанции: nil,
        допущенныеПослеТерминализации: nil
      )
      _ = try допуститьОжидающиеРесурсныеПопытки(&состояние)
      guard let результат = состояние.ресурсныеПопытки[попытка] else {
        throw ОшибкаКорневогоРеестраЗапусков("ресурсная_попытка_исчезла")
      }
      return try решениеРесурсногоРаспределения(результат, состояние: состояние)
    }
  }

  public func изменитьСостояниеРесурснойСессии(
    попытка: String,
    хэшДопуска: String,
    новоеСостояние: СостояниеРесурснойСессии
  ) throws -> РешениеРесурсногоДопуска {
    try изменитьСРезультатом { состояние in
      guard var запись = состояние.ресурсныеПопытки[попытка],
        let назначение = состояние.ресурсныеНазначения[запись.назначение],
        запись.хэшДопуска == хэшДопуска,
        запись.состояние != .ожидаетРесурсы,
        запись.состояние != .завершена,
        допустимыйПереходРесурснойСессии(
          из: запись.состояние,
          в: новоеСостояние,
          класс: назначение.спецификация.классСессии
        )
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неверный_переход_ресурсной_сессии")
      }
      let прежняяМаска = запись.маска
      let новаяМаска: МаскаРесурсногоВыделения
      if [.остановкаЗапрошена, .отменаЗапрошена, .внешнийИсходНеизвестен]
        .contains(новоеСостояние)
      {
        новаяМаска = прежняяМаска
      } else {
        новаяМаска = маскаРесурсногоВыделения(
          для: новоеСостояние,
          класс: назначение.спецификация.классСессии
        )
      }
      if маскаУвеличиваетЁмкость(с: прежняяМаска, до: новаяМаска),
        !ресурснаяЁмкостьДопускает(
          назначение.спецификация,
          маска: новаяМаска,
          состояние: состояние,
          исключая: попытка
        )
      {
        throw ОшибкаКорневогоРеестраЗапусков("превышен_предел_ресурсной_ёмкости")
      }
      запись.состояние = новоеСостояние
      запись.маска = новаяМаска
      состояние.ресурсныеПопытки[попытка] = запись
      if маскаОсвобождаетРесурс(с: прежняяМаска, до: новаяМаска) {
        _ = try допуститьОжидающиеРесурсныеПопытки(&состояние)
      }
      guard let результат = состояние.ресурсныеПопытки[попытка] else {
        throw ОшибкаКорневогоРеестраЗапусков("ресурсная_попытка_исчезла")
      }
      return try решениеРесурсногоРаспределения(результат, состояние: состояние)
    }

  public func сохранитьПредактивацию(поколение: String) throws -> String {
    let исходнаяЗапись = try прочитатьПоколение(поколение)
    guard исходнаяЗапись.фаза == .подготовка else {
      throw ОшибкаКорневогоРеестраЗапусков("неверная_фаза_предактивации")
    }
    for ветвь in исходнаяЗапись.ветви.values {
      _ = try проверитьФактическуюРабочуюКопию(
        ветвь: ветвь,
        поколение: исходнаяЗапись
      )
    }
    return try изменитьСРезультатом { состояние in
      guard var запись = состояние.поколения[поколение],
        запись == исходнаяЗапись,
        запись.фаза == .подготовка
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неверная_фаза_предактивации")
      }
      guard запись.ветви.count == 2,
        запись.ветви.values.allSatisfy({
          $0.попытка.состояние == .подтверждена
            && $0.каталогГит != nil && $0.общийКаталогГит != nil
        }),
        Set(запись.ветви.values.compactMap(\.попытка.подтверждённыйСеанс)).count == 2,
        Set(запись.ветви.values.compactMap(\.идентификаторОбщегоКаталога)).count == 2
      else {
        throw ОшибкаКорневогоРеестраЗапусков("пара_не_готова_к_предактивации")
      }
      let нагрузка = try неизменяемаяНагрузка(запись)
      let хэшНагрузки = хэш(try каноническиеДанные(нагрузка))
      let отпечаток = хэш(
        try каноническиеДанные([
          "поколение": запись.идентификатор,
          "хэш_замороженной_нагрузки": хэшНагрузки,
        ])
      )
      запись.фаза = .предактивация
      запись.хэшПредактивации = отпечаток
      запись.хэшЗамороженнойНагрузки = хэшНагрузки
      состояние.поколения[поколение] = запись
      return отпечаток
    }
  }

  public func активироватьПару(
    поколение: String,
    ожидаемыйХэш: String
  ) throws -> КвитанцияАктивацииКорневогоЗапуска {
    func хэшиПривязок(_ запись: ЗаписьПоколенияКорневогоЗапуска) throws -> [String] {
      try запись.ветви.values.sorted { $0.сторона.rawValue < $1.сторона.rawValue }.map {
        guard let задача = $0.попытка.идентификаторЗадачи,
          let среда = $0.попытка.идентификаторСреды
        else {
          throw ОшибкаКорневогоРеестраЗапусков("неполная_host_привязка")
        }
        let нагрузка = НагрузкаХэшаПривязкиЗадачи(
          схема: "корневая-привязка-задачи.1",
          поколение: запись.идентификатор,
          исходнаяВершина: запись.исходнаяВершина,
          форк: $0.форк,
          попытка: $0.попытка.идентификатор,
          идентификаторЗадачи: задача,
          идентификаторСреды: среда,
          хэшКонверта: $0.попытка.хэшКонверта
        )
        return хэш(try каноническиеДанные(нагрузка))
      }.sorted()
    }
    func квитанцияАктивации(
      запись: ЗаписьПоколенияКорневогоЗапуска,
      хэшКвитанции: String
    ) throws -> КвитанцияАктивацииКорневогоЗапуска {
      let привязки = try хэшиПривязок(запись)
      let доказательство = НагрузкаДоказательстваАктивацииПары(
        схема: "корневая-активация-пары.1",
        поколение: поколение,
        хэшПредактивации: ожидаемыйХэш,
        хэшКвитанции: хэшКвитанции,
        хэшиПривязок: привязки
      )
      return КвитанцияАктивацииКорневогоЗапуска(
        поколение: поколение,
        хэшПредактивации: ожидаемыйХэш,
        хэшКвитанции: хэшКвитанции,
        хэшиПривязок: привязки,
        хэшДоказательстваАктивации: хэш(try каноническиеДанные(доказательство))
      )
    }
    let исходнаяЗапись = try прочитатьПоколение(поколение)
    if исходнаяЗапись.фаза == .активация,
      исходнаяЗапись.хэшПредактивации == ожидаемыйХэш,
      let квитанция = исходнаяЗапись.хэшКвитанции
    {
      return try квитанцияАктивации(запись: исходнаяЗапись, хэшКвитанции: квитанция)
    }
    guard исходнаяЗапись.фаза == .предактивация,
      исходнаяЗапись.хэшПредактивации == ожидаемыйХэш,
      let сохранённыйХэшНагрузки = исходнаяЗапись.хэшЗамороженнойНагрузки
    else {
      throw ОшибкаКорневогоРеестраЗапусков("устаревшее_ограждение_активации")
    }
    guard
      хэш(try каноническиеДанные(неизменяемаяНагрузка(исходнаяЗапись)))
        == сохранённыйХэшНагрузки
    else {
      throw ОшибкаКорневогоРеестраЗапусков("изменившаяся_замороженная_нагрузка")
    }
    for ветвь in исходнаяЗапись.ветви.values {
      let проверка: ПровереннаяРабочаяКопия
      do {
        проверка = try проверитьФактическуюРабочуюКопию(
          ветвь: ветвь,
          поколение: исходнаяЗапись
        )
      } catch {
        throw ОшибкаКорневогоРеестраЗапусков("изменившийся_клон_перед_активацией")
      }
      guard проверка.каталогГит == ветвь.каталогГит,
        проверка.общийКаталогГит == ветвь.общийКаталогГит,
        проверка.идентификаторОбщегоКаталога == ветвь.идентификаторОбщегоКаталога
      else {
        throw ОшибкаКорневогоРеестраЗапусков("изменившийся_клон_перед_активацией")
      }
    }
    return try изменитьСРезультатом { состояние in
      guard var запись = состояние.поколения[поколение] else {
        throw ОшибкаКорневогоРеестраЗапусков("неизвестное_поколение")
      }
      if запись.фаза == .активация,
        запись.хэшПредактивации == ожидаемыйХэш,
        let квитанция = запись.хэшКвитанции
      {
        return try квитанцияАктивации(запись: запись, хэшКвитанции: квитанция)
      }
      guard запись.фаза == .предактивация,
        запись == исходнаяЗапись,
        запись.хэшПредактивации == ожидаемыйХэш,
        запись.хэшЗамороженнойНагрузки == сохранённыйХэшНагрузки
      else {
        throw ОшибкаКорневогоРеестраЗапусков("устаревшее_ограждение_активации")
      }
      for ветвь in запись.ветви.values {
        let проверка: ПровереннаяРабочаяКопия
        do {
          проверка = try проверитьФактическуюРабочуюКопию(
            ветвь: ветвь,
            поколение: запись
          )
        } catch {
          throw ОшибкаКорневогоРеестраЗапусков("изменившийся_клон_перед_активацией")
        }
        guard проверка.каталогГит == ветвь.каталогГит,
          проверка.общийКаталогГит == ветвь.общийКаталогГит,
          проверка.идентификаторОбщегоКаталога == ветвь.идентификаторОбщегоКаталога
        else {
          throw ОшибкаКорневогоРеестраЗапусков("изменившийся_клон_перед_активацией")
        }
      }
      let квитанция = хэш(
        Data("активация\u{0}поколение:\(поколение)\u{0}предактивация:\(ожидаемыйХэш)".utf8))
      запись.фаза = .активация
      запись.хэшКвитанции = квитанция
      состояние.поколения[поколение] = запись
      состояние.числоАктиваций += 1
      return try квитанцияАктивации(запись: запись, хэшКвитанции: квитанция)
    }
  }

  public func разрешитьВходВОчередь(
    поколение: String,
    сторона: СторонаВетвевогоФорка,
    идентификаторЗадачи: String,

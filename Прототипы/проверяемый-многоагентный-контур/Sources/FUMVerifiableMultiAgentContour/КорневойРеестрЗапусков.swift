private final class БлокировкаКорневогоРеестра {
  private var дескриптор: Int32

  init(адрес: URL) throws {
    дескриптор = адрес.path.withCString {
      open($0, O_RDWR | O_CREAT | O_CLOEXEC | O_NOFOLLOW, 0o600)
    }
    guard дескриптор >= 0 else { throw ОшибкаКорневогоРеестраЗапусков("небезопасная_блокировка") }
    var метаданные = stat()
    guard fstat(дескриптор, &метаданные) == 0,
      метаданные.st_mode & S_IFMT == S_IFREG,
      метаданные.st_nlink == 1,
      flock(дескриптор, LOCK_EX) == 0
    else {
      _ = close(дескриптор)
      дескриптор = -1
      throw ОшибкаКорневогоРеестраЗапусков("небезопасная_блокировка")
    }
  }

  func освободить() {
    guard дескриптор >= 0 else { return }
    _ = flock(дескриптор, LOCK_UN)
    _ = close(дескриптор)
    дескриптор = -1
  }

  deinit { освободить() }
}

private enum ХранениеКорневогоРеестра {
  static func существует(_ адрес: URL) -> Bool {
    var метаданные = stat()
    return адрес.path.withCString { lstat($0, &метаданные) } == 0
  }

  static func обеспечитьКаталог(_ адрес: URL) throws {
    if существует(адрес) {
      var метаданные = stat()
      guard адрес.path.withCString({ lstat($0, &метаданные) }) == 0,
        метаданные.st_mode & S_IFMT == S_IFDIR
      else { throw ОшибкаКорневогоРеестраЗапусков("небезопасный_каталог_реестра") }
      return
    }
    try FileManager.default.createDirectory(
      at: адрес, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
  }

  static func прочитать(_ адрес: URL) throws -> Data {
    let дескриптор = адрес.path.withCString { open($0, O_RDONLY | O_CLOEXEC | O_NOFOLLOW) }
    guard дескриптор >= 0 else {
      throw ОшибкаКорневогоРеестраЗапусков("невозможно_прочитать_реестр")
    }
    defer { _ = close(дескриптор) }
    var метаданные = stat()
    guard fstat(дескриптор, &метаданные) == 0,
      метаданные.st_mode & S_IFMT == S_IFREG,
      метаданные.st_nlink == 1,
      метаданные.st_size >= 0,
      метаданные.st_size <= 16 * 1_024 * 1_024
    else { throw ОшибкаКорневогоРеестраЗапусков("небезопасный_файл_реестра") }
    let файл = FileHandle(fileDescriptor: дескриптор, closeOnDealloc: false)
    return try файл.readToEnd() ?? Data()
  }

  static func сохранить(_ данные: Data, по адрес: URL) throws {
    let временный = адрес.deletingLastPathComponent().appendingPathComponent(
      ".tmp-\(UUID().uuidString)")
    let дескриптор = временный.path.withCString {
      open($0, O_WRONLY | O_CREAT | O_EXCL | O_CLOEXEC | O_NOFOLLOW, 0o600)
    }
    guard дескриптор >= 0 else {
      throw ОшибкаКорневогоРеестраЗапусков("невозможно_сохранить_реестр")
    }
    var открыт = true
    defer {
      if открыт { _ = close(дескриптор) }
      _ = временный.path.withCString { unlink($0) }
    }
    let успех = данные.withUnsafeBytes { буфер -> Bool in
      guard let основа = буфер.baseAddress else { return данные.isEmpty }
      var смещение = 0
      while смещение < данные.count {
        let число = Darwin.write(дескриптор, основа.advanced(by: смещение), данные.count - смещение)
        if число < 0 {
          if errno == EINTR { continue }
          return false
        }
        смещение += число
      }
      return true
    }
    guard успех, fsync(дескриптор) == 0, close(дескриптор) == 0 else {
      throw ОшибкаКорневогоРеестраЗапусков("невозможно_сохранить_реестр")
    }
    открыт = false
    guard
      временный.path.withCString({ источник in
        адрес.path.withCString { цель in rename(источник, цель) }
      }) == 0
    else {
      throw ОшибкаКорневогоРеестраЗапусков("невозможно_опубликовать_реестр")
    }
    let каталог = адрес.deletingLastPathComponent()
    let каталогДескриптор = каталог.path.withCString {
      open($0, O_RDONLY | O_DIRECTORY | O_CLOEXEC | O_NOFOLLOW)
    }
    guard каталогДескриптор >= 0, fsync(каталогДескриптор) == 0 else {
      if каталогДескриптор >= 0 { _ = close(каталогДескриптор) }
      throw ОшибкаКорневогоРеестраЗапусков("невозможно_синхронизировать_реестр")
    }
    _ = close(каталогДескриптор)
  }
}

private func каноническиеДанные<Значение: Encodable>(_ значение: Значение) throws -> Data {

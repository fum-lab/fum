  public func материализоватьИПроверитьКлон(
    поколение: String,
    сторона: СторонаВетвевогоФорка
  ) throws {
    let ветвь = try прочитатьВетвь(поколение: поколение, сторона: сторона)
    let адрес = URL(fileURLWithPath: ветвь.локальныйПуть, isDirectory: true)
    guard !ХранениеКорневогоРеестра.существует(адрес) else {
      throw ОшибкаКорневогоРеестраЗапусков("целевая_рабочая_копия_уже_существует")
    }
    _ = try командаГит(
      ["clone", "--no-checkout", "--no-local", ветвь.источник, адрес.path],
      корень: адрес.deletingLastPathComponent()
    )
    let поколениеЗапись = try прочитатьПоколение(поколение)
    let краткаяСсылка = String(ветвь.ссылка.dropFirst("refs/heads/".count))
    _ = try командаГит(
      ["checkout", "--detach", поколениеЗапись.исходнаяВершина], корень: адрес)
    _ = try командаГит(
      ["switch", "-c", краткаяСсылка], корень: адрес)
    try проверитьИСвязатьРабочуюКопию(поколение: поколение, сторона: сторона)
  }

  func проверитьИСвязатьРабочуюКопию(
    поколение: String,
    сторона: СторонаВетвевогоФорка
  ) throws {
    try изменить { состояние in
      guard var поколениеЗапись = состояние.поколения[поколение],
        var текущая = поколениеЗапись.ветви[сторона.rawValue]
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неизвестная_ветвь")
      }
      guard поколениеЗапись.фаза == .подготовка,
        текущая.попытка.состояние == .подготовлена
      else {
        throw ОшибкаКорневогоРеестраЗапусков("рабочая_копия_уже_заморожена")
      }
      let проверка = try проверитьФактическуюРабочуюКопию(
        ветвь: текущая,
        поколение: поколениеЗапись
      )
      if let владелец = состояние.общиеКаталоги[проверка.общийКаталогГит],
        владелец != текущая.форк
      {
        throw ОшибкаКорневогоРеестраЗапусков("общий_каталог_гит_уже_зарезервирован")
      }
      состояние.общиеКаталоги[проверка.общийКаталогГит] = текущая.форк
      текущая.каталогГит = проверка.каталогГит
      текущая.общийКаталогГит = проверка.общийКаталогГит
      текущая.идентификаторОбщегоКаталога = проверка.идентификаторОбщегоКаталога
      текущая.попытка.хэшКонверта = try сформироватьЗапросСоздания(
        поколение: поколениеЗапись,
        ветвь: текущая
      ).хэшКонверта
      поколениеЗапись.ветви[сторона.rawValue] = текущая
      состояние.поколения[поколение] = поколениеЗапись
    }
  }

  public func выполнитьЕдинственныйВызов(
    поколение: String,
    сторона: СторонаВетвевогоФорка,
    среда: СредаСозданияЗадач
  ) throws {
    let запрос = try зафиксироватьНамерениеВызова(
      поколение: поколение,
      сторона: сторона
    )

    let исход = среда.создать(запрос)
    switch исход {
    case .точный(let задача, let среда):
      guard !задача.isEmpty, !среда.isEmpty else {
        try сделатьПопыткуНеизвестной(
          поколение: поколение,
          сторона: сторона,
          видимыеСвязи: [ВидимаяСвязьСозданнойЗадачи(задача: задача, среда: среда)]
        )
        throw ОшибкаКорневогоРеестраЗапусков("неполный_ответ_среды")
      }
      try сохранитьОтвет(поколение: поколение, сторона: сторона, задача: задача, среда: среда)
    case .неполный(let задача, let среда):
      try сделатьПопыткуНеизвестной(
        поколение: поколение,
        сторона: сторона,
        видимыеСвязи: [ВидимаяСвязьСозданнойЗадачи(задача: задача, среда: среда)]
      )
      throw ОшибкаКорневогоРеестраЗапусков("неполный_ответ_среды")
    case .потерян(let задача, let среда):
      try сделатьПопыткуНеизвестной(
        поколение: поколение,
        сторона: сторона,
        видимыеСвязи: [ВидимаяСвязьСозданнойЗадачи(задача: задача, среда: среда)]
      )
      throw ОшибкаКорневогоРеестраЗапусков("неизвестный_ответ_среды")
    case .остановленДоСвязывания:
      try сделатьПопыткуНеизвестной(поколение: поколение, сторона: сторона)
      throw ОшибкаКорневогоРеестраЗапусков("остановка_до_привязки")
    }
  }

  @discardableResult
  func зафиксироватьНамерениеВызова(
    поколение: String,
    сторона: СторонаВетвевогоФорка
  ) throws -> ЗапросСозданияЗадачи {
    try изменитьСРезультатом { состояние in
      guard var поколениеЗапись = состояние.поколения[поколение],
        var ветвь = поколениеЗапись.ветви[сторона.rawValue]
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неизвестная_ветвь")
      }
      guard поколениеЗапись.фаза == .подготовка else {
        throw ОшибкаКорневогоРеестраЗапусков("поколение_уже_заморожено")
      }
      guard
        поколениеЗапись.ветви.values.allSatisfy({
          $0.попытка.состояние != .вызовНачат && $0.попытка.состояние != .неизвестна
        })
      else {
        throw ОшибкаКорневогоРеестраЗапусков("неразрешённая_попытка_блокирует_вызов")
      }
      guard ветвь.попытка.состояние == .подготовлена,
        ветвь.попытка.числоВызовов == 0,
        !ветвь.попытка.хэшКонверта.isEmpty,
        ветвь.каталогГит != nil,
        ветвь.общийКаталогГит != nil
      else {
        throw ОшибкаКорневогоРеестраЗапусков("попытка_уже_могла_создать_задачу")
      }
      let запрос = try сформироватьЗапросСоздания(
        поколение: поколениеЗапись,
        ветвь: ветвь
      )
      guard запрос.хэшКонверта == ветвь.попытка.хэшКонверта else {
        throw ОшибкаКорневогоРеестраЗапусков("изменившийся_конверт_создания")
      }
      ветвь.попытка.состояние = .вызовНачат
      ветвь.попытка.числоВызовов = 1
      поколениеЗапись.ветви[сторона.rawValue] = ветвь
      состояние.поколения[поколение] = поколениеЗапись
      return запрос
    }
  }

  public func восстановитьТочнуюПопытку(
    поколение: String,
    сторона: СторонаВетвевогоФорка,
    среда: СредаСозданияЗадач
  ) throws {
    let запись = try прочитатьПоколение(поколение)
    guard запись.фаза == .подготовка else {
      throw ОшибкаКорневогоРеестраЗапусков("поколение_уже_заморожено")
    }
    guard let ветвь = запись.ветви[сторона.rawValue],
      ветвь.попытка.состояние == .вызовНачат
        || ветвь.попытка.состояние == .неизвестна
    else {
      throw ОшибкаКорневогоРеестраЗапусков("попытка_не_требует_восстановления")
    }
    let запрос = try сформироватьЗапросСоздания(поколение: запись, ветвь: ветвь)
    guard запрос.хэшКонверта == ветвь.попытка.хэшКонверта else {
      throw ОшибкаКорневогоРеестраЗапусков("изменившийся_конверт_создания")
    }
    let ответы = среда.прочитатьПопытку(запрос)
    guard ответы.count == 1 else {
      try сделатьПопыткуНеизвестной(
        поколение: поколение,
        сторона: сторона,
        видимыеСвязи: ответы.map {
          ВидимаяСвязьСозданнойЗадачи(
            задача: $0.идентификаторЗадачи,
            среда: $0.идентификаторСреды
          )
        }
      )
      throw ОшибкаКорневогоРеестраЗапусков("авторитетный_результат_не_единственный")
    }
    let доказательство = ответы[0]
    guard доказательство.запрос == запрос,
      !доказательство.идентификаторЗадачи.isEmpty,
      !доказательство.идентификаторСреды.isEmpty
    else {
      try сделатьПопыткуНеизвестной(
        поколение: поколение,
        сторона: сторона,
        видимыеСвязи: [
          ВидимаяСвязьСозданнойЗадачи(
            задача: доказательство.идентификаторЗадачи,
            среда: доказательство.идентификаторСреды
          )
        ]
      )
      throw ОшибкаКорневогоРеестраЗапусков("несовпавший_авторитетный_результат")
    }
    try сохранитьОтвет(
      поколение: поколение,
      сторона: сторона,
      задача: доказательство.идентификаторЗадачи,
      среда: доказательство.идентификаторСреды
    )
  }


private func хэш(_ данные: Data) -> String {
  "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}

private func ключРабочейПары(_ репозиторий: String, _ ссылка: String) -> String {
  "\(репозиторий)\u{0}\(ссылка)"
}

private func зарезервироватьНеоднозначнуюСвязь(
  состояние: inout СостояниеКорневогоРеестраЗапусков,
  ограждение: String,
  задача: String?,
  среда: String?
) {
  if let задача, проверитьНепустоеОграждение(задача), состояние.задачиСреды[задача] == nil {
    состояние.задачиСреды[задача] = ограждение
  }
  if let среда, проверитьНепустоеОграждение(среда), состояние.средыЗадач[среда] == nil {
    состояние.средыЗадач[среда] = ограждение
  }
}

private func проверитьВершину(_ значение: String) -> Bool {
  (значение.count == 40 || значение.count == 64)
    && значение.unicodeScalars.allSatisfy {
      (48...57).contains(Int($0.value)) || (97...102).contains(Int($0.value))
    }
}

private func проверитьНепустоеОграждение(_ значение: String) -> Bool {
  !значение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    && !значение.contains("\u{0}")
}

private func каноническийПуть(_ адрес: URL) -> URL {
  адрес.standardizedFileURL.resolvingSymlinksInPath()
}

private func каноническийЦелевойПуть(_ адрес: URL) -> URL {
  let стандартизованный = адрес.standardizedFileURL
  return каноническийПуть(стандартизованный.deletingLastPathComponent())
    .appendingPathComponent(стандартизованный.lastPathComponent, isDirectory: true)
}

private func идентичностьСуществующегоКаталога(_ адрес: URL) throws -> String {
  let канонический = каноническийПуть(адрес)
  var метаданные = stat()
  guard канонический.path.withCString({ lstat($0, &метаданные) }) == 0,
    метаданные.st_mode & S_IFMT == S_IFDIR
  else {
    throw ОшибкаКорневогоРеестраЗапусков("небезопасная_физическая_идентичность")
  }
  return "устройство:\(метаданные.st_dev);индекс:\(метаданные.st_ino)"
}

private func идентичностьФизическогоИсточника(_ адрес: URL) throws -> String {
  let канонический = каноническийПуть(адрес)
  let путьОбъектов = try командаГит(
    ["rev-parse", "--git-path", "objects"],
    корень: канонический
  )
  let каталогОбъектов = каноническийПуть(
    URL(fileURLWithPath: путьОбъектов, relativeTo: канонический)
  )
  return try идентичностьСуществующегоКаталога(каталогОбъектов)
}

private func идентичностьЦелевойРабочейКопии(_ адрес: URL) throws -> String {
  let канонический = каноническийЦелевойПуть(адрес)
  let родитель = канонический.deletingLastPathComponent()
  return try
    "родитель:\(идентичностьСуществующегоКаталога(родитель));имя:\(канонический.lastPathComponent)"
}

private func командаГит(_ аргументы: [String], корень: URL) throws -> String {
  let процесс = Process()
  процесс.executableURL = WritingSubnodeSystemRuntime.gitExecutableURL
  процесс.arguments =
    [
      "-c", "protocol.allow=never",
      "-c", "protocol.file.allow=always",
      "-c", "core.hooksPath=\(WritingSubnodeSystemRuntime.nullDevicePath)",
      "-c", "core.autocrlf=false",
      "-c", "core.filemode=false",
    ] + аргументы
  процесс.currentDirectoryURL = корень
  процесс.environment = [
    "PATH": ProcessInfo.processInfo.environment["PATH"] ?? "",
    "LC_ALL": "C",
    "LANG": "C",
    "TZ": "UTC",
    "GIT_CONFIG_NOSYSTEM": "1",
    "GIT_CONFIG_GLOBAL": WritingSubnodeSystemRuntime.nullDevicePath,
    "GIT_TERMINAL_PROMPT": "0",
  ]
  let вывод = Pipe()
  процесс.standardOutput = вывод
  процесс.standardError = вывод
  процесс.standardInput = FileHandle.nullDevice
  try процесс.run()
  try? вывод.fileHandleForWriting.close()
  let данные = вывод.fileHandleForReading.readDataToEndOfFile()
  процесс.waitUntilExit()
  guard процесс.terminationReason == .exit, процесс.terminationStatus == 0 else {
    throw ОшибкаКорневогоРеестраЗапусков("команда_гит_не_выполнена")
  }
  return String(decoding: данные, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)
}

private func разрешитьПутьГит(_ путь: String, относительно корень: URL) throws -> URL {
  let адрес = URL(fileURLWithPath: путь, relativeTo: корень).standardizedFileURL
    .resolvingSymlinksInPath()
  var метаданные = stat()
  guard адрес.path.withCString({ lstat($0, &метаданные) }) == 0,
    метаданные.st_mode & S_IFMT == S_IFDIR
  else { throw ОшибкаКорневогоРеестраЗапусков("небезопасный_каталог_гит") }
  return адрес
}

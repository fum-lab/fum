    let захват = try ЛокальныеИнструментыПроекта.диспетчер(
      корень: корень,
      путь: путьДиспетчера,
      команда: "claim",
      аргументы: [
        "--expected-branch-ref", ожидаемаяВетка,
        "--expected-step-id", ожидаемыйШаг,

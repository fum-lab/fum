      путь: контур.путьДиспетчера,
      команда: "rearm",
      аргументы: [
        "--expected-branch-ref", контур.ветка,
        "--expected-step-id", контур.идентификаторШага,
        "--expected-selection-id", контур.идентификаторВыбора,
        "--expected-lease-id", контур.идентификаторАренды,
        "--task-id", контур.идентификаторЗадачи,
        "--generation", контур.поколение,
      ])
    guard повторнаяГотовность["state"] as? String == "rearmed" else {
      throw ОшибкаРепозиторияПроекта.подготовка("Fixture не сняла собственный claim.")
    }
    let завершение = try ЛокальныеИнструментыПроекта.очередь(
      корень: контур.корень,
      путь: контур.путьОчереди,
      аргументы: [
        "finish-clean", "--task-id", контур.идентификаторЗадачи,
        "--generation", контур.поколение,
      ])
    guard завершение["state"] as? String == "finished_clean" else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Fixture не завершила собственное чистое поколение очереди.")
    }
  }

  fileprivate static func выполнитьСквознойСценарий(
    _ окружение: ОкружениеФикстурыПроекта
  ) throws -> ОтчётСценарияПроекта {
    let гит = окружение.гит
    let (начальнаяРегистрация, нарушенияРегистрации) =
      try ПредварительнаяПроверкаПроекта.проверитьРодительскуюРегистрацию(
        коммитРодителя: окружение.исходныйКоммитРодителя,
        репозиторийРодителя: окружение.репозиторийРодителя,
        репозиторийПроекта: окружение.репозиторийПроекта,
        путьПроекта: окружение.путьПроекта,
        гит: гит)
    let нарушенияПаспорта = try ПредварительнаяПроверкаПроекта.проверитьПаспорт(
      данные: окружение.данныеПаспорта,
      коммит: окружение.исходныйКоммитПроекта,
      репозиторий: окружение.репозиторийПроекта,
      живойКлон: окружение.живойКлонПроекта,
      родительскийКлон: окружение.управляющийКлонРодителя,
      гит: гит)
    guard нарушенияПаспорта.isEmpty, нарушенияРегистрации.isEmpty,
      let начальнаяРегистрация
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Положительная fixture не прошла исходный preflight.")
    }

    let родительскийКонтур = try занятьКонтур(
      корень: окружение.управляющийКлонРодителя,
      путьОчереди: окружение.путьОчереди,
      путьДиспетчера: окружение.путьДиспетчера,
      ожидаемаяВетка: "refs/heads/main",
      ожидаемыйШаг: "parent-fixture-step-0001-automatic-v1",
      идентификаторАренды: "11111111-1111-4111-8111-111111111111",
      идентификаторЗадачи: "11111111-1111-4111-8111-222222222222",
      гит: гит)
    let проектныйКонтур = try занятьКонтур(
      корень: окружение.живойКлонПроекта,
      путьОчереди: окружение.путьОчереди,
      путьДиспетчера: окружение.путьДиспетчера,
      ожидаемаяВетка: "refs/heads/project-main",
      ожидаемыйШаг: "project-fixture-step-0001-automatic-v1",
      идентификаторАренды: "22222222-2222-4222-8222-111111111111",
      идентификаторЗадачи: "22222222-2222-4222-8222-222222222222",
      гит: гит)
    let голыйПроектБезСлужебныхСсылок = try гит.text(
      ["for-each-ref", "--format=%(refname)", "refs/fum/"],
      at: окружение.репозиторийПроекта
    ).isEmpty
    let голыйРодительБезСлужебныхСсылок = try гит.text(
      ["for-each-ref", "--format=%(refname)", "refs/fum/"],
      at: окружение.репозиторийРодителя
    ).isEmpty
    let управляющиеСсылкиРаздельны =
      проектныйКонтур.ссылкаОчереди != родительскийКонтур.ссылкаОчереди
      && проектныйКонтур.ссылкаЗахвата != родительскийКонтур.ссылкаЗахвата
      && проектныйКонтур.ссылкаОчереди.hasPrefix("refs/fum/worktree-task-queues/")
      && проектныйКонтур.ссылкаЗахвата.hasPrefix("refs/fum/worktree-next-step-claims/")
      && голыйПроектБезСлужебныхСсылок
      && голыйРодительБезСлужебныхСсылок
    try завершитьКонтур(проектныйКонтур)
    try завершитьКонтур(родительскийКонтур)

    let вершинаРодителяПередШагом = try DurableForkValidation.refOID(
      "refs/heads/main", repository: окружение.репозиторийРодителя, git: гит)
    let итоговыйКоммитПроекта = try создатьКоммитПроектногоШага(окружение)
    let родительНеИзменёнПроектом =
      try DurableForkValidation.refOID(
        "refs/heads/main", repository: окружение.репозиторийРодителя, git: гит)
      == вершинаРодителяПередШагом
    let обновление = try обновитьРодительскуюСсылкуПодмодуля(
      окружение, новаяСсылкаПодмодуля: итоговыйКоммитПроекта)
    let непринятаяВершинаПроекта = try продвинутьЖивуюВеткуПослеИнтеграции(
      окружение,
      принятыйКоммит: итоговыйКоммитПроекта,
      неизменныйКоммитРодителя: обновление.коммит)

    let свежийКлон = try проверитьСвежийКлон(
      окружение,
      коммитРодителя: обновление.коммит,
      ссылкаПодмодуля: итоговыйКоммитПроекта)
    let финальныйОтчётКомпозиции = try ОкружениеФикстурыПроекта.отчётКомпозиции(
      коммитРодителя: обновление.коммит,
      коммитПроекта: итоговыйКоммитПроекта,
      базовыйКоммитПроекта: окружение.исходныйКоммитПроекта,
      репозиторийРодителя: окружение.репозиторийРодителя,
      репозиторийПроекта: окружение.репозиторийПроекта,
      снимокРодителя: свежийКлон.корень,
      писатель: окружение.живойКлонПроекта,
      путьПроекта: окружение.путьПроекта,
      закрытыйДоступ: false,
      цикл: false)
    let (_, финальныеНарушенияРегистрации) =
      try ПредварительнаяПроверкаПроекта.проверитьРодительскуюРегистрацию(
        коммитРодителя: обновление.коммит,
        репозиторийРодителя: окружение.репозиторийРодителя,
        репозиторийПроекта: окружение.репозиторийПроекта,
        путьПроекта: окружение.путьПроекта,
        гит: гит)
    let локальность = try проверитьЛокальность(
      окружение, свежийКлон: свежийКлон.корень)

    let точнаяПроектнаяВершина =
      try DurableForkValidation.refOID(
        "refs/heads/project-main", repository: окружение.репозиторийПроекта, git: гит)
      == непринятаяВершинаПроекта
    let принятыйКоммитСохранёнВИстории = try гит.succeeds(
      ["merge-base", "--is-ancestor", итоговыйКоммитПроекта, непринятаяВершинаПроекта],
      at: окружение.репозиторийПроекта)
    let живаяВеткаОпережаетПринятуюСсылкуПодмодуля =
      непринятаяВершинаПроекта != итоговыйКоммитПроекта
      && принятыйКоммитСохранёнВИстории
    let проверки = [
      проверка(
        "проект-имеет-собственную-репозиторную-идентичность",
        окружение.регистрация.проект.repositoryID == "repository.project.fixture"
          && окружение.регистрация.проект.repositoryID
            != "repository.parent.fixture"
          && точнаяПроектнаяВершина),
      проверка(
        "паспорт-хранит-полный-контракт",
        нарушенияПаспорта.isEmpty && окружение.данныеПаспорта != nil),
      проверка(
        "проект-хранит-собственные-правила-очередь-claim-и-следующий-шаг",
        проектныйКонтур.ветка == "refs/heads/project-main"
          && проектныйКонтур.идентификаторШага
            == "project-fixture-step-0001-automatic-v1"
      ),
      проверка(
        "очередь-и-claim-привязаны-к-физическому-checkout",
        управляющиеСсылкиРаздельны),
      проверка(
        "родитель-хранит-только-композиционную-регистрацию",
        начальнаяРегистрация.проект.kind == .project
          && финальныеНарушенияРегистрации.isEmpty),
      проверка(
        "родительский-путь-является-точным-gitlink",
        окружение.отчётКомпозиции.decision == .valid
          && финальныйОтчётКомпозиции.decision == .valid),
      проверка(
        "пишущий-шаг-выполнен-в-отдельном-клоне",
        родительНеИзменёнПроектом
          && итоговыйКоммитПроекта != окружение.исходныйКоммитПроекта),
      проверка(
        "обновление-gitlink-является-отдельным-CAS-коммитом",
        обновление.точноеИзменение && обновление.единственныйРодитель),
      проверка(
        "живой-ref-проекта-опережает-принятый-gitlink",
        живаяВеткаОпережаетПринятуюСсылкуПодмодуля
          && свежийКлон.ссылкаПодмодуля == итоговыйКоммитПроекта),
      проверка(
        "свежий-клон-без-материализации-сохраняет-точную-ревизию",
        свежийКлон.былНематериализован
          && свежийКлон.ссылкаПодмодуля == итоговыйКоммитПроекта),
      проверка(
        "материализованный-снимок-detached-и-чист",
        свежийКлон.отделён && свежийКлон.чист),
      проверка(
        "сценарий-использует-только-локальные-bare-репозитории",
        локальность),
    ]
    let неожиданныеСсылки = try !точныеИтоговыеСсылки(
      окружение,
      коммитПроекта: непринятаяВершинаПроекта,
      коммитРодителя: обновление.коммит)
    return отчёт(
      сценарий: "сквозной-сценарий",
      проверки: проверки,
      хэшПаспорта: окружение.данныеПаспорта.map(DurableForkJSON.sha256),
      исходныйКоммитПроекта: окружение.исходныйКоммитПроекта,
      итоговыйКоммитПроекта: непринятаяВершинаПроекта,
      исходныйКоммитРодителя: окружение.исходныйКоммитРодителя,
      итоговыйКоммитРодителя: обновление.коммит,
      неожиданныеСсылки: неожиданныеСсылки)
  }

  fileprivate static func выполнитьОтрицательныйСценарий(
    _ имя: String,
    окружение: ОкружениеФикстурыПроекта
  ) throws -> ОтчётСценарияПроекта {
    let до = try СнимокСсылокПроекта.прочитать(
      проект: окружение.репозиторийПроекта,
      родитель: окружение.репозиторийРодителя,
      гит: окружение.гит)
    let живойКлон =
      имя == "общий-checkout"
      ? окружение.управляющийКлонРодителя : окружение.живойКлонПроекта
    let нарушенияПаспорта = try ПредварительнаяПроверкаПроекта.проверитьПаспорт(
      данные: окружение.данныеПаспорта,
      коммит: окружение.исходныйКоммитПроекта,
      репозиторий: окружение.репозиторийПроекта,
      живойКлон: живойКлон,
      родительскийКлон: окружение.управляющийКлонРодителя,
      гит: окружение.гит)
    let (_, нарушенияРегистрации) =
      try ПредварительнаяПроверкаПроекта.проверитьРодительскуюРегистрацию(
        коммитРодителя: окружение.исходныйКоммитРодителя,
        репозиторийРодителя: окружение.репозиторийРодителя,
        репозиторийПроекта: окружение.репозиторийПроекта,
        путьПроекта: окружение.путьПроекта,
        гит: окружение.гит)
    let отклонено: Bool
    let идентификаторПроверки: String
    switch имя {
    case "обычный-каталог-вместо-gitlink":
      отклонено =
        нарушенияРегистрации.contains("parent_path_not_gitlink")
        && окружение.отчётКомпозиции.decision == .invalid
      идентификаторПроверки = "обычный-каталог-отклонён"
    case "нет-паспорта":
      отклонено = нарушенияПаспорта.contains("project_passport_missing")
      идентификаторПроверки = "проект-без-паспорта-отклонён"
    case "нет-следующего-шага":
      отклонено = нарушенияПаспорта.contains("project_next_step_missing")
      идентификаторПроверки = "проект-без-следующего-шага-отклонён"
    case "общий-checkout":
      отклонено =
        нарушенияПаспорта.contains("project_checkout_not_separate")
        && окружение.отчётКомпозиции.decision == .invalid
      идентификаторПроверки = "общий-checkout-с-родителем-отклонён"
    case "неверный-gitlink":
      отклонено = нарушенияРегистрации.contains("parent_gitlink_mismatch")
      идентификаторПроверки = "неверный-gitlink-отклонён"
    case "цикл":
      отклонено =
        окружение.отчётКомпозиции.decision == .invalid
        && окружение.отчётКомпозиции.violations.contains { $0.code == "repository_cycle" }
      идентификаторПроверки = "цикл-репозиторной-композиции-отклонён"
    case "недоступная-публикация":
      отклонено =
        окружение.отчётКомпозиции.decision == .invalid
        && окружение.отчётКомпозиции.violations.contains { $0.code == "incompatible_access" }
      идентификаторПроверки = "недоступная-публикация-отклонена"
    default:
      throw ОшибкаРепозиторияПроекта.неизвестнаяФикстура(имя)
    }
    let после = try СнимокСсылокПроекта.прочитать(
      проект: окружение.репозиторийПроекта,
      родитель: окружение.репозиторийРодителя,
      гит: окружение.гит)
    let неожиданныеСсылки = до != после
    return отчёт(
      сценарий: имя,
      проверки: [проверка(идентификаторПроверки, отклонено)],
      хэшПаспорта: окружение.данныеПаспорта.map(DurableForkJSON.sha256),
      исходныйКоммитПроекта: окружение.исходныйКоммитПроекта,
      итоговыйКоммитПроекта: окружение.исходныйКоммитПроекта,
      исходныйКоммитРодителя: окружение.исходныйКоммитРодителя,
      итоговыйКоммитРодителя: окружение.исходныйКоммитРодителя,
      неожиданныеСсылки: неожиданныеСсылки)
  }
}


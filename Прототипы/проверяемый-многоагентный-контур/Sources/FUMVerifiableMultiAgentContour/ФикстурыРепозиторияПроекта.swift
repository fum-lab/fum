    }
    let допуск = try ЛокальныеИнструментыПроекта.очередь(
      корень: корень,
      путь: путьОчереди,
      аргументы: ["join", "--task-id", идентификаторЗадачи])
    guard допуск["state"] as? String == "admitted",
      let поколение = допуск["generation"] as? String,
      let ссылкаОчереди = допуск["queue_ref"] as? String
    else {
      throw ОшибкаРепозиторияПроекта.подготовка("Fixture не получила допуск своей очереди.")
    }
    let привязка = try ЛокальныеИнструментыПроекта.диспетчер(
      корень: корень,
      путь: путьДиспетчера,
      команда: "bind-run",
      аргументы: [
        "--expected-branch-ref", ожидаемаяВетка,
        "--expected-step-id", ожидаемыйШаг,
        "--expected-selection-id", идентификаторВыбора,
        "--expected-lease-id", идентификаторАренды,
        "--task-id", идентификаторЗадачи,
      ])
    let подтверждение = try ЛокальныеИнструментыПроекта.диспетчер(
      корень: корень,
      путь: путьДиспетчера,
      команда: "verify-run",
      аргументы: [
        "--expected-branch-ref", ожидаемаяВетка,
        "--expected-step-id", ожидаемыйШаг,
        "--expected-selection-id", идентификаторВыбора,
        "--expected-lease-id", идентификаторАренды,
        "--task-id", идентификаторЗадачи,
        "--generation", поколение,
      ])
    guard привязка["state"] as? String == "bound",
      подтверждение["state"] as? String == "verified"
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Run-fence fixture не подтвердил очередь и claim.")
    }
    let ссылкиЗахвата = try гит.text(
      ["for-each-ref", "--format=%(refname)", "refs/fum/worktree-next-step-claims/"],
      at: корень
    ).split(separator: "\n").map(String.init)
    guard ссылкиЗахвата.count == 1, let ссылкаЗахвата = ссылкиЗахвата.first else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Fixture не обнаружила единственную локальную ссылку claim.")
    }
    return ЗанятыйКонтурПроекта(
      корень: корень,
      путьОчереди: путьОчереди,
      путьДиспетчера: путьДиспетчера,
      ветка: ожидаемаяВетка,
      идентификаторШага: ожидаемыйШаг,
      идентификаторВыбора: идентификаторВыбора,
      идентификаторАренды: идентификаторАренды,
      идентификаторЗадачи: идентификаторЗадачи,
      поколение: поколение,
      ссылкаОчереди: ссылкаОчереди,
      ссылкаЗахвата: ссылкаЗахвата

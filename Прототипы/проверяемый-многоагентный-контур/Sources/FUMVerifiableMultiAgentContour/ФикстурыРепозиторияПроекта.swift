extension ФикстурыРепозиторияПроекта {
  fileprivate static func создатьКоммитПроектногоШага(
    _ окружение: ОкружениеФикстурыПроекта
  ) throws -> String {
    let гит = окружение.гит
    guard
      try гит.text(
        ["rev-parse", "--verify", "HEAD^{commit}"], at: окружение.живойКлонПроекта)
        == окружение.исходныйКоммитПроекта,
      try гит.text(
        ["status", "--porcelain=v1", "--untracked-files=all"],
        at: окружение.живойКлонПроекта
      ).isEmpty
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Живой проектный клон изменился до пишущего шага.")
    }
    let путь = "Результаты/состояние.md"
    let данные = Data(
      "# Состояние\n\nОдин автономный шаг проекта выполнен и проверен.\n".utf8)
    try WritingSubnodePersistence.materialize(
      WritingSubnodeWrite(path: путь, contents: данные),
      cloneURL: окружение.живойКлонПроекта)
    _ = try гит.data(["add", "--", путь], at: окружение.живойКлонПроекта)
    let дерево = try гит.text(["write-tree"], at: окружение.живойКлонПроекта)
    let коммит = try гит.text(
      ["commit-tree", дерево, "-p", окружение.исходныйКоммитПроекта],
      at: окружение.живойКлонПроекта,
      input: Data("Выполнить автономный шаг проекта\n".utf8),
      additionalEnvironment: DurableForkValidation.commitEnvironment)
    guard
      try DurableForkValidation.pushCAS(
        newOID: коммит,
        expectedOID: окружение.исходныйКоммитПроекта,
        ref: "refs/heads/project-main",
        clone: окружение.живойКлонПроекта,
        git: гит
      )
    else {
      throw ОшибкаРепозиторияПроекта.подготовка("CAS проектной ветки проигран.")
    }
    let обновление = Data(
      "start\nupdate refs/heads/project-main \(коммит) \(окружение.исходныйКоммитПроекта)\nprepare\ncommit\n"
        .utf8)
    _ = try гит.data(
      ["update-ref", "--stdin"], at: окружение.живойКлонПроекта, input: обновление)
    _ = try гит.data(["reset", "--hard", "--quiet", коммит], at: окружение.живойКлонПроекта)
    let изменённыеПути = try гит.nulStrings(
      [
        "diff-tree", "--no-commit-id", "--name-only", "-r", "-z",
        окружение.исходныйКоммитПроекта, коммит, "--",
      ], at: окружение.репозиторийПроекта)
    let родители = try гит.text(
      ["rev-list", "--parents", "-n", "1", коммит], at: окружение.репозиторийПроекта
    )
    .split(separator: " ").dropFirst().map(String.init)
    guard изменённыеПути == [путь], родители == [окружение.исходныйКоммитПроекта] else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Проектный шаг вышел за разрешённый путь или родословную.")
    }
    return коммит
  }

  fileprivate static func обновитьРодительскуюСсылкуПодмодуля(
    _ окружение: ОкружениеФикстурыПроекта,
    новаяСсылкаПодмодуля: String
  ) throws -> ОбновлениеРодителяПроекта {
    let гит = окружение.гит
    let текущаяВершина = try DurableForkValidation.refOID(
      "refs/heads/main", repository: окружение.репозиторийРодителя, git: гит)
    guard текущаяВершина == окружение.исходныйКоммитРодителя,
      try гит.succeeds(
        [
          "merge-base", "--is-ancestor", окружение.исходныйКоммитПроекта,
          новаяСсылкаПодмодуля,
        ],
        at: окружение.репозиторийПроекта),
      try DurableForkValidation.refOID(
        "refs/heads/project-main", repository: окружение.репозиторийПроекта, git: гит)
        == новаяСсылкаПодмодуля
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "CAS-preflight родителя не подтвердил ожидаемые вершины.")
    }
    let клон = окружение.корень.appending(
      path: "parent-update", directoryHint: .isDirectory)
    _ = try гит.data(
      [
        "clone", "--quiet", "--no-local", "--no-hardlinks", "--no-checkout", "--",
        окружение.репозиторийРодителя.path, клон.path,
      ], at: окружение.корень)
    _ = try гит.data(
      ["checkout", "--quiet", "--detach", окружение.исходныйКоммитРодителя, "--"],
      at: клон)
    let фактическаяСтараяСсылкаПодмодуля = try DurableForkValidation.gitlink(
      parentOID: окружение.исходныйКоммитРодителя,
      path: окружение.путьПроекта,
      repository: окружение.репозиторийРодителя,
      git: гит)
    guard фактическаяСтараяСсылкаПодмодуля == окружение.исходныйКоммитПроекта else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Родительский gitlink изменился до CAS-интеграции.")
    }
    let регистрация = ОкружениеФикстурыПроекта.регистрацияПроекта(
      базовыйКоммитПроекта: окружение.исходныйКоммитПроекта,
      ссылкаПодмодуля: новаяСсылкаПодмодуля,
      путьПроекта: окружение.путьПроекта,
      закрытыйДоступ: false,
      цикл: false)
    try WritingSubnodePersistence.materialize(
      WritingSubnodeWrite(
        path: ПредварительнаяПроверкаПроекта.путьРегистрации,
        contents: try регистрация.каноническиеДанные()),
      cloneURL: клон)
    _ = try гит.data(
      ["add", "--", ПредварительнаяПроверкаПроекта.путьРегистрации], at: клон)
    _ = try гит.data(
      [
        "update-index", "--add", "--cacheinfo",
        "160000,\(новаяСсылкаПодмодуля),\(окружение.путьПроекта)",
      ], at: клон)
    let изменённыеПути = try гит.nulStrings(
      [
        "diff", "--cached", "--name-only", "-z", окружение.исходныйКоммитРодителя,
        "--",
      ], at: клон)
    let ожидаемыеПути = [
      ПредварительнаяПроверкаПроекта.путьРегистрации, окружение.путьПроекта,
    ].sorted()
    let точноеИзменение = изменённыеПути.sorted() == ожидаемыеПути
    guard точноеИзменение else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Родительская интеграция изменила неожиданные пути.")
    }
    let дерево = try гит.text(["write-tree"], at: клон)
    let коммит = try гит.text(
      ["commit-tree", дерево, "-p", окружение.исходныйКоммитРодителя], at: клон,
      input: Data("Обновить точный gitlink самостоятельного проекта\n".utf8),
      additionalEnvironment: DurableForkValidation.commitEnvironment)
    guard
      try DurableForkValidation.pushCAS(
        newOID: коммит,
        expectedOID: окружение.исходныйКоммитРодителя,
        ref: "refs/heads/main",
        clone: клон,
        git: гит
      )
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "CAS родительского интеграционного коммита проигран.")
    }
    let родители = try гит.text(
      ["rev-list", "--parents", "-n", "1", коммит], at: окружение.репозиторийРодителя
    )
    .split(separator: " ").dropFirst().map(String.init)
    return ОбновлениеРодителяПроекта(
      коммит: коммит,
      точноеИзменение: точноеИзменение,
      единственныйРодитель: родители == [окружение.исходныйКоммитРодителя]
    )
  }

  fileprivate static func продвинутьЖивуюВеткуПослеИнтеграции(
    _ окружение: ОкружениеФикстурыПроекта,
    принятыйКоммит: String,
    неизменныйКоммитРодителя: String
  ) throws -> String {
    let гит = окружение.гит
    guard
      try DurableForkValidation.refOID(
        "refs/heads/project-main", repository: окружение.репозиторийПроекта, git: гит)
        == принятыйКоммит,
      try DurableForkValidation.refOID(
        "refs/heads/main", repository: окружение.репозиторийРодителя, git: гит)
        == неизменныйКоммитРодителя,
      try гит.text(
        ["rev-parse", "--verify", "HEAD^{commit}"], at: окружение.живойКлонПроекта)
        == принятыйКоммит
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Вершины изменились до проверки неподвижности принятого gitlink.")
    }

    let путь = "Результаты/непринятая-вершина.md"
    try WritingSubnodePersistence.materialize(
      WritingSubnodeWrite(
        path: путь,
        contents: Data("# Непринятая вершина\n\nЖивая ветка опережает снимок композиции.\n".utf8)
      ),
      cloneURL: окружение.живойКлонПроекта)
    _ = try гит.data(["add", "--", путь], at: окружение.живойКлонПроекта)
    let дерево = try гит.text(["write-tree"], at: окружение.живойКлонПроекта)
    let коммит = try гит.text(
      ["commit-tree", дерево, "-p", принятыйКоммит],
      at: окружение.живойКлонПроекта,
      input: Data("Продвинуть живую ветку после принятого снимка\n".utf8),
      additionalEnvironment: DurableForkValidation.commitEnvironment)
    guard
      try DurableForkValidation.pushCAS(
        newOID: коммит,
        expectedOID: принятыйКоммит,
        ref: "refs/heads/project-main",
        clone: окружение.живойКлонПроекта,
        git: гит)
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "CAS непринятой вершины проектной ветки проигран.")
    }
    let обновление = Data(
      "start\nupdate refs/heads/project-main \(коммит) \(принятыйКоммит)\nprepare\ncommit\n".utf8)
    _ = try гит.data(
      ["update-ref", "--stdin"], at: окружение.живойКлонПроекта, input: обновление)
    _ = try гит.data(
      ["reset", "--hard", "--quiet", коммит], at: окружение.живойКлонПроекта)
    guard
      try DurableForkValidation.refOID(
        "refs/heads/main", repository: окружение.репозиторийРодителя, git: гит)
        == неизменныйКоммитРодителя
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Продвижение живой проектной ветки изменило родительский ref.")
    }
    return коммит
  }

  fileprivate static func проверитьСвежийКлон(
    _ окружение: ОкружениеФикстурыПроекта,
    коммитРодителя: String,
    ссылкаПодмодуля: String
  ) throws -> СвежийКлонПроекта {
    let гит = окружение.гит
    let корень = окружение.корень.appending(
      path: "fresh-parent", directoryHint: .isDirectory)
    _ = try гит.data(
      [
        "clone", "--quiet", "--no-local", "--no-hardlinks", "--no-checkout", "--",
        окружение.репозиторийРодителя.path, корень.path,
      ], at: окружение.корень)
    _ = try гит.data(["checkout", "--quiet", "--detach", коммитРодителя, "--"], at: корень)
    let прочитаннаяСсылкаПодмодуля = try DurableForkValidation.gitlink(
      parentOID: коммитРодителя,
      path: окружение.путьПроекта,
      repository: корень,
      git: гит)
    let состояниеДо = try гит.text(
      ["submodule", "status", "--", окружение.путьПроекта], at: корень)
    let путьСнимка = корень.appending(
      path: окружение.путьПроекта, directoryHint: .isDirectory)
    let снимокУжеЯвляетсяРепозиторием = FileManager.default.fileExists(
      atPath: путьСнимка.appending(path: ".git").path)
    let былНематериализован =
      прочитаннаяСсылкаПодмодуля == ссылкаПодмодуля
      && состояниеДо.hasPrefix("-")
      && !снимокУжеЯвляетсяРепозиторием
    _ = try гит.data(
      ["submodule", "update", "--init", "--", окружение.путьПроекта], at: корень)
    let голова = try гит.text(["rev-parse", "--verify", "HEAD^{commit}"], at: путьСнимка)
    let отделён = !(try гит.succeeds(["symbolic-ref", "-q", "HEAD"], at: путьСнимка))
    let чист = try гит.text(
      ["status", "--porcelain=v1", "--untracked-files=all"], at: путьСнимка
    ).isEmpty
    guard голова == ссылкаПодмодуля else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "Явная materialization восстановила не тот проектный коммит.")
    }
    return СвежийКлонПроекта(
      корень: корень,
      ссылкаПодмодуля: прочитаннаяСсылкаПодмодуля ?? "",
      былНематериализован: былНематериализован,
      отделён: отделён,
      чист: чист)
  }

  fileprivate static func проверитьЛокальность(
    _ окружение: ОкружениеФикстурыПроекта,
    свежийКлон: URL
  ) throws -> Bool {
    let гит = окружение.гит
    guard try DurableForkValidation.isBare(окружение.репозиторийПроекта, git: гит),
      try DurableForkValidation.isBare(окружение.репозиторийРодителя, git: гит)
    else { return false }
    let клоны = [
      окружение.живойКлонПроекта, окружение.управляющийКлонРодителя, свежийКлон,
    ]
    for клон in клоны {
      let адрес = try гит.text(["remote", "get-url", "origin"], at: клон)
      guard !адрес.contains("://"), !адрес.contains("@"),
        URL(fileURLWithPath: адрес).standardizedFileURL.path
          .hasPrefix(окружение.корень.standardizedFileURL.path + "/")
      else { return false }
    }
    let модули = try гит.text(
      ["show", "HEAD:.gitmodules"], at: свежийКлон)
    let служебныеСсылкиГолыхРепозиториев =
      try гит.text(
        ["for-each-ref", "--format=%(refname)", "refs/fum/"],
        at: окружение.репозиторийПроекта)
      + (try гит.text(
        ["for-each-ref", "--format=%(refname)", "refs/fum/"],
        at: окружение.репозиторийРодителя))
    return модули.contains("url = ../project.git")
      && служебныеСсылкиГолыхРепозиториев.isEmpty
  }

  fileprivate static func точныеИтоговыеСсылки(
    _ окружение: ОкружениеФикстурыПроекта,
    коммитПроекта: String,
    коммитРодителя: String
  ) throws -> Bool {
    let проектныеСсылки = try окружение.гит.text(
      ["for-each-ref", "--format=%(refname) %(objectname)"],
      at: окружение.репозиторийПроекта)
    let родительскиеСсылки = try окружение.гит.text(
      ["for-each-ref", "--format=%(refname) %(objectname)"],
      at: окружение.репозиторийРодителя)
    return проектныеСсылки == "refs/heads/project-main \(коммитПроекта)"
      && родительскиеСсылки == "refs/heads/main \(коммитРодителя)"
  }


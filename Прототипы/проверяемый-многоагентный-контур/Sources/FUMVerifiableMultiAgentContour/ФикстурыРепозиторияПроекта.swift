      показ["state"] as? String == "ready",
      показ["branch_ref"] as? String == ожидаемаяВетка,
      показ["step_id"] as? String == ожидаемыйШаг,
      let выбор = показ["selection"] as? [String: Any],
      let идентификаторВыбора = выбор["id"] as? String

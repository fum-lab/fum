extension ФикстурыРепозиторияПроекта {
  fileprivate static func занятьКонтур(
    корень: URL,
    путьОчереди: String,
    путьДиспетчера: String,
    ожидаемаяВетка: String,
    ожидаемыйШаг: String,
    идентификаторАренды: String,
    идентификаторЗадачи: String,
    гит: CandidateIntegrationGit
  ) throws -> ЗанятыйКонтурПроекта {

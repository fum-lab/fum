import Foundation

public enum ФикстурыРепозиторияПроекта {
  public static let идентификаторы = [
    "сквозной-сценарий",
    "обычный-каталог-вместо-gitlink",
    "нет-паспорта",
    "нет-следующего-шага",
    "общий-checkout",
    "неверный-gitlink",
    "цикл",
    "недоступная-публикация",
  ]

  public static func выполнить(имя: String) throws -> ОтчётСценарияПроекта {
    guard идентификаторы.contains(имя) else {
      throw ОшибкаРепозиторияПроекта.неизвестнаяФикстура(имя)
    }
    let корень = FileManager.default.temporaryDirectory.appending(
      path: "fum-project-fixture-\(UUID().uuidString)", directoryHint: .isDirectory)
    try FileManager.default.createDirectory(at: корень, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: корень) }
    let окружение = try ОкружениеФикстурыПроекта.создать(корень: корень, сценарий: имя)
    if имя == "сквозной-сценарий" {
      return try выполнитьСквознойСценарий(окружение)
    }
    return try выполнитьОтрицательныйСценарий(имя, окружение: окружение)
  }
}

private struct ОкружениеФикстурыПроекта {
  let корень: URL
  let гит: CandidateIntegrationGit
  let репозиторийПроекта: URL
  let репозиторийРодителя: URL
  let живойКлонПроекта: URL
  let управляющийКлонРодителя: URL
  let снимокРодителя: URL
  let исходныйКоммитПроекта: String
  let исходныйКоммитРодителя: String
  let базовыйКоммитРодителя: String
  let путьПроекта: String
  let путьОчереди: String
  let путьДиспетчера: String
  let путьРабочегоНабораПроекта: String
  let путьКарточкиПроекта: String
  let путьРабочегоНабораРодителя: String
  let путьКарточкиРодителя: String
  let данныеПаспорта: Data?
  let регистрация: РегистрацияПроекта
  let отчётКомпозиции: RepositoryCompositionReport

  static func создать(корень: URL, сценарий: String) throws -> ОкружениеФикстурыПроекта {
    let гит = CandidateIntegrationGit()
    let исходныйКорень = try найтиКореньИсходников()
    let путьОчереди =
      "Инструменты/fum-ocheredj-zadach-git-vetki/scripts/ocheredj-zadach-git-vetki.py"
    let путьДиспетчера =
      "Инструменты/fum-sleduyusjhij-shag-vetki/scripts/branch-next-step.py"
    let данныеОчереди = try Data(contentsOf: исходныйКорень.appending(path: путьОчереди))
    let данныеДиспетчера = try Data(
      contentsOf: исходныйКорень.appending(path: путьДиспетчера))
    let репозиторийРодителя = корень.appending(
      path: "parent.git", directoryHint: .isDirectory)
    let репозиторийПроекта = корень.appending(
      path: "project.git", directoryHint: .isDirectory)

    let путьКарточкиРодителя =
      "Планирование/карточки-шагов/🟡-FUM-STEP-9003-проверить-родительскую-композицию.md"
    let путьРабочегоНабораРодителя = "Планирование/следующие-шаги-веток/main.md"
    let данныеКарточкиРодителя = карточка(
      идентификатор: "FUM-STEP-9003", заголовок: "Проверить родительскую композицию")
    let данныеНабораРодителя = рабочийНабор(
      ветка: "refs/heads/main",
      путьПроекта: "README.md",
      идентификаторШага: "parent-fixture-step-0001-automatic-v1",
      идентификаторКарточки: "FUM-STEP-9003",
      путьКарточки: путьКарточкиРодителя,
      данныеКарточки: данныеКарточкиРодителя
    )
    let базовыеФайлыРодителя: [String: Data] = [
      "README.md": Data("# Родительская композиция fixture\n".utf8),
      "AGENTS.md": Data(
        "# Правила родителя\n\nРодитель использует собственную очередь независимо от проекта.\n"
          .utf8),
      путьОчереди: данныеОчереди,
      путьДиспетчера: данныеДиспетчера,
      путьКарточкиРодителя: данныеКарточкиРодителя,
      путьРабочегоНабораРодителя: данныеНабораРодителя,
    ]
    let базовыйКоммитРодителя = try создатьНачальныйРепозиторий(
      голыйРепозиторий: репозиторийРодителя,
      ветка: "refs/heads/main",
      имяКлона: "parent-seed",
      файлы: базовыеФайлыРодителя,
      сообщение: "Создать родительскую композицию fixture",
      корень: корень,
      гит: гит
    )

    let путьКарточкиПроекта =
      "Планирование/карточки-шагов/🟡-FUM-STEP-9002-выполнить-шаг-проекта.md"
    let путьРабочегоНабораПроекта = "Планирование/следующие-шаги-веток/project-main.md"
    let данныеКарточкиПроекта = карточка(
      идентификатор: "FUM-STEP-9002", заголовок: "Выполнить шаг проекта")
    let данныеНабораПроекта = рабочийНабор(
      ветка: "refs/heads/project-main",
      путьПроекта: "README.md",
      идентификаторШага: "project-fixture-step-0001-automatic-v1",
      идентификаторКарточки: "FUM-STEP-9002",
      путьКарточки: путьКарточкиПроекта,
      данныеКарточки: данныеКарточкиПроекта
    )
    let паспорт = ПаспортПроекта(
      идентификаторСхемы: "urn:fum:schema:project-passport:v1",
      версияСхемы: 1,
      идентификаторПроекта: "project.independent.fixture",
      идентификаторРепозитория: "repository.project.fixture",
      адресРепозитория: "urn:fum:repository:project-fixture",
      цель: "Проверить автономный жизненный цикл самостоятельного проекта FUM.",
      рабочаяСсылка: "refs/heads/project-main",
      уровеньДоступа: .public,
      границаПубликации: .public,
      путьПравил: "AGENTS.md",
      пространствоСсылокОчереди: "refs/fum/worktree-task-queues",
      путьОчереди: путьОчереди,
      пространствоСсылокЗахвата: "refs/fum/worktree-next-step-claims",
      путьДиспетчера: путьДиспетчера,
      путьРабочегоНабора: путьРабочегоНабораПроекта,
      хэшРабочегоНабора: DurableForkJSON.sha256(данныеНабораПроекта),
      путьКарточки: путьКарточкиПроекта,
      источники: ["urn:fum:requirement:FUM-REQ-0027"],
      проверки: [
        "project-passport", "project-control-plane", "project-parent-gitlink",
      ],
      условиеЗавершения: "Проектный коммит принят, а родительский gitlink обновлён отдельным CAS."
    )
    let каноническийПаспорт = try паспорт.каноническиеДанные()
    var файлыПроекта: [String: Data] = [
      "README.md": Data(
        """
        # Паспорт самостоятельного проекта fixture

        Проект проверяет автономный жизненный цикл отдельного Git-репозитория.

        Машинный паспорт: [Паспорт-проекта.json](Паспорт-проекта.json).
        Правила: [AGENTS.md](AGENTS.md).
        Рабочий набор: [project-main.md](Планирование/следующие-шаги-веток/project-main.md).
        """.appending("\n").utf8),
      "AGENTS.md": Data(
        """
        # Правила самостоятельного проекта fixture

        Проект изменяется только в собственном физическом checkout. Его очередь, claim и диспетчер не используют состояние родительского checkout.
        """.appending("\n").utf8),
      путьОчереди: данныеОчереди,
      путьДиспетчера: данныеДиспетчера,
      путьКарточкиПроекта: данныеКарточкиПроекта,
      путьРабочегоНабораПроекта: данныеНабораПроекта,
      "Результаты/состояние.md": Data("# Состояние\n\nШаг ещё не выполнен.\n".utf8),
    ]
    if сценарий != "нет-паспорта" {
      файлыПроекта[ПредварительнаяПроверкаПроекта.путьПаспорта] = каноническийПаспорт
    }
    if сценарий == "нет-следующего-шага" {
      файлыПроекта.removeValue(forKey: путьРабочегоНабораПроекта)
    }
    if сценарий == "цикл" {
      файлыПроекта[".gitmodules"] = Data(
        """
        [submodule "parent-cycle"]
        \tpath = Предки/родитель
        \turl = ../parent.git
        """.appending("\n").utf8)
    }
    let исходныйКоммитПроекта = try создатьПроектныйРепозиторий(
      голыйРепозиторий: репозиторийПроекта,
      файлы: файлыПроекта,
      ссылкаПодмодуляРодителя: сценарий == "цикл" ? базовыйКоммитРодителя : nil,
      корень: корень,
      гит: гит
    )

    let путьПроекта = "Проекты/самостоятельный"
    let закрытыйДоступ = сценарий == "недоступная-публикация"
    let объявленнаяСсылкаПодмодуля =
      сценарий == "неверный-gitlink"
      ? String(repeating: "f", count: 40) : исходныйКоммитПроекта
    let регистрация = регистрацияПроекта(
      базовыйКоммитПроекта: исходныйКоммитПроекта,
      ссылкаПодмодуля: объявленнаяСсылкаПодмодуля,
      путьПроекта: путьПроекта,
      закрытыйДоступ: закрытыйДоступ,
      цикл: сценарий == "цикл"
    )
    let исходныйКоммитРодителя = try создатьРегистрациюРодителя(
      репозиторий: репозиторийРодителя,
      базовыйКоммит: базовыйКоммитРодителя,
      ссылкаПодмодуля: исходныйКоммитПроекта,
      регистрация: регистрация,
      путьПроекта: путьПроекта,
      обычныйКаталог: сценарий == "обычный-каталог-вместо-gitlink",
      корень: корень,
      гит: гит
    )

    let живойКлонПроекта = корень.appending(path: "project-live", directoryHint: .isDirectory)
    try клонироватьВетку(
      голыйРепозиторий: репозиторийПроекта,
      в: живойКлонПроекта,
      ветка: "project-main",
      гит: гит)
    let управляющийКлонРодителя = корень.appending(
      path: "parent-control", directoryHint: .isDirectory)
    try клонироватьВетку(
      голыйРепозиторий: репозиторийРодителя,
      в: управляющийКлонРодителя,
      ветка: "main",
      гит: гит)
    let снимокРодителя = корень.appending(
      path: "parent-snapshot", directoryHint: .isDirectory)
    try клонироватьСнимок(
      голыйРепозиторий: репозиторийРодителя,
      в: снимокРодителя,
      коммит: исходныйКоммитРодителя,
      путьПроекта: путьПроекта,
      материализовать: сценарий != "обычный-каталог-вместо-gitlink",
      гит: гит)

    let данныеПаспорта = try? гит.data(
      [
        "cat-file", "blob",
        "\(исходныйКоммитПроекта):\(ПредварительнаяПроверкаПроекта.путьПаспорта)",
      ],
      at: репозиторийПроекта)
    let контекстПисателя =
      сценарий == "общий-checkout"
      ? управляющийКлонРодителя : живойКлонПроекта
    let отчётКомпозиции = try отчётКомпозиции(
      коммитРодителя: исходныйКоммитРодителя,
      коммитПроекта: исходныйКоммитПроекта,
      базовыйКоммитПроекта: исходныйКоммитПроекта,
      репозиторийРодителя: репозиторийРодителя,
      репозиторийПроекта: репозиторийПроекта,
      снимокРодителя: снимокРодителя,
      писатель: контекстПисателя,
      путьПроекта: путьПроекта,
      закрытыйДоступ: закрытыйДоступ,
      цикл: сценарий == "цикл"
    )
    return ОкружениеФикстурыПроекта(
      корень: корень,
      гит: гит,
      репозиторийПроекта: репозиторийПроекта,
      репозиторийРодителя: репозиторийРодителя,
      живойКлонПроекта: живойКлонПроекта,
      управляющийКлонРодителя: управляющийКлонРодителя,
      снимокРодителя: снимокРодителя,
      исходныйКоммитПроекта: исходныйКоммитПроекта,
      исходныйКоммитРодителя: исходныйКоммитРодителя,
      базовыйКоммитРодителя: базовыйКоммитРодителя,
      путьПроекта: путьПроекта,
      путьОчереди: путьОчереди,
      путьДиспетчера: путьДиспетчера,
      путьРабочегоНабораПроекта: путьРабочегоНабораПроекта,
      путьКарточкиПроекта: путьКарточкиПроекта,
      путьРабочегоНабораРодителя: путьРабочегоНабораРодителя,
      путьКарточкиРодителя: путьКарточкиРодителя,
      данныеПаспорта: данныеПаспорта,
      регистрация: регистрация,
      отчётКомпозиции: отчётКомпозиции
    )
  }
}

extension ОкружениеФикстурыПроекта {
  fileprivate static func найтиКореньИсходников() throws -> URL {
    let начала = [
      URL(fileURLWithPath: FileManager.default.currentDirectoryPath, isDirectory: true),
      Bundle.module.bundleURL,
    ]
    for начало in начала {
      var кандидат = начало.standardizedFileURL
      for _ in 0..<16 {
        if FileManager.default.fileExists(atPath: кандидат.appending(path: "AGENTS.md").path) {
          return кандидат
        }
        кандидат.deleteLastPathComponent()
      }
    }
    throw ОшибкаРепозиторияПроекта.подготовка(
      "Не найден корень исходного checkout для автономной проектной фикстуры.")
  }

  fileprivate static func карточка(идентификатор: String, заголовок: String) -> Data {
    Data(
      """
      +++
      schema_version = 1
      card_id = "\(идентификатор)"
      status = "active"
      +++
      # \(заголовок)

      Карточка задаёт один ограниченный автономный шаг локальной фикстуры.

      ## Задача

      Выполнить проверяемое действие только в собственном репозитории.

      ## Почему сейчас

      Репозиторий готов к одному автономному шагу.

      ## Критерии завершения

      - Собственная очередь допускает шаг.
      - Результат шага сохраняется в собственной ветке.

      ## Источники

      - Локальный паспорт fixture.
      """.appending("\n").utf8)
  }

  fileprivate static func рабочийНабор(
    ветка: String,
    путьПроекта: String,
    идентификаторШага: String,
    идентификаторКарточки: String,
    путьКарточки: String,
    данныеКарточки: Data
  ) -> Data {
    Data(
      """
      +++
      schema_version = 5
      branch_ref = "\(ветка)"
      state = "open"
      project_path = "\(путьПроекта)"

      [[candidates]]
      step_id = "\(идентификаторШага)"
      dispatch = "automatic"
      card_id = "\(идентификаторКарточки)"
      card_content_sha256 = "\(DurableForkJSON.sha256(данныеКарточки))"
      requires_completed_card_ids = []
      +++
      # Выбрать следующий шаг fixture

      Рабочий набор содержит один проверяемый автоматический кандидат.
      """.appending("\n").utf8)
  }

  fileprivate static func регистрацияПроекта(
    базовыйКоммитПроекта: String,
    ссылкаПодмодуля: String,
    путьПроекта: String,
    закрытыйДоступ: Bool,
    цикл: Bool
  ) -> РегистрацияПроекта {
    let проверки = ["project-passport", "project-control-plane", "project-parent-gitlink"]
    return РегистрацияПроекта(
      идентификаторСхемы: "urn:fum:schema:project-registration:v1",
      версияСхемы: 1,
      проект: RepositoryCompositionChild(
        entryID: "entry.project.fixture",
        kind: .project,
        nodeID: nil,
        projectID: "project.independent.fixture",
        targetRepositoryID: nil,
        repositoryID: "repository.project.fixture",
        repositoryURL: "urn:fum:repository:project-fixture",
        upstreamRepositoryID: nil,
        baseOID: базовыйКоммитПроекта,
        liveRef: "refs/heads/project-main",
        submodulePath: путьПроекта,
        gitlinkOID: ссылкаПодмодуля,
        snapshotMode: "detached_read_only",
        writerMode: "separate_clone",
        nestedSubmodules: цикл
          ? [
            RepositoryCompositionNestedSubmodule(
              repositoryID: "repository.parent.fixture",
              submodulePath: "Предки/родитель")
          ] : [],
        accessLevel: закрытыйДоступ ? .private : .public,
        publicationBoundary: закрытыйДоступ ? .private : .public,
        checks: проверки,
        handoff: RepositoryCompositionHandoff(
          targetRepositoryID: "repository.parent.fixture",
          targetRef: "refs/heads/main",
          requiredCheckIDs: проверки
        )
      )
    )
  }

  fileprivate static func создатьНачальныйРепозиторий(
    голыйРепозиторий: URL,
    ветка: String,
    имяКлона: String,
    файлы: [String: Data],
    сообщение: String,
    корень: URL,
    гит: CandidateIntegrationGit
  ) throws -> String {
    let краткаяВетка = String(ветка.dropFirst("refs/heads/".count))
    _ = try гит.data(
      [
        "init", "--quiet", "--bare", "--initial-branch=\(краткаяВетка)", "--",
        голыйРепозиторий.path,
      ],
      at: корень)
    let клон = корень.appending(path: имяКлона, directoryHint: .isDirectory)
    _ = try гит.data(
      [
        "clone", "--quiet", "--no-local", "--no-hardlinks", "--no-checkout", "--",
        голыйРепозиторий.path, клон.path,
      ], at: корень)
    for (путь, данные) in файлы.sorted(by: { $0.key < $1.key }) {
      try WritingSubnodePersistence.materialize(
        WritingSubnodeWrite(path: путь, contents: данные), cloneURL: клон)
      _ = try гит.data(["add", "--", путь], at: клон)
    }
    let дерево = try гит.text(["write-tree"], at: клон)
    let коммит = try гит.text(
      ["commit-tree", дерево], at: клон, input: Data((сообщение + "\n").utf8),
      additionalEnvironment: DurableForkValidation.commitEnvironment)
    _ = try гит.data(["push", "--porcelain", "origin", "\(коммит):\(ветка)"], at: клон)
    return коммит
  }

  fileprivate static func создатьПроектныйРепозиторий(
    голыйРепозиторий: URL,
    файлы: [String: Data],
    ссылкаПодмодуляРодителя: String?,
    корень: URL,
    гит: CandidateIntegrationGit
  ) throws -> String {
    let командаИнициализации = "init"
    _ = try гит.data(
      [
        командаИнициализации, "--quiet", "--bare", "--initial-branch=project-main", "--",
        голыйРепозиторий.path,
      ],
      at: корень)
    let клон = корень.appendingPathComponent("project-seed")
    _ = try гит.data(
      [
        "clone", "--quiet", "--no-local", "--no-hardlinks", "--no-checkout", "--",
        голыйРепозиторий.path, клон.path,
      ], at: корень)
    for (путь, данные) in файлы.sorted(by: { $0.key < $1.key }) {
      try WritingSubnodePersistence.materialize(
        WritingSubnodeWrite(path: путь, contents: данные), cloneURL: клон)
      _ = try гит.data(["add", "--", путь], at: клон)
    }
    if let ссылкаПодмодуляРодителя {
      _ = try гит.data(
        [
          "update-index", "--add", "--cacheinfo",
          "160000,\(ссылкаПодмодуляРодителя),Предки/родитель",
        ], at: клон)
    }
    let дерево = try гит.text(["write-tree"], at: клон)
    let коммит = try гит.text(
      ["commit-tree", дерево], at: клон,
      input: Data("Создать самостоятельный проект fixture\n".utf8),
      additionalEnvironment: DurableForkValidation.commitEnvironment)
    _ = try гит.data(
      ["push", "--porcelain", "origin", "\(коммит):refs/heads/project-main"], at: клон)
    return коммит
  }

  fileprivate static func создатьРегистрациюРодителя(
    репозиторий: URL,
    базовыйКоммит: String,
    ссылкаПодмодуля: String,
    регистрация: РегистрацияПроекта,
    путьПроекта: String,
    обычныйКаталог: Bool,
    корень: URL,
    гит: CandidateIntegrationGit
  ) throws -> String {
    let клон = корень.appending(path: "parent-registration", directoryHint: .isDirectory)
    _ = try гит.data(
      [
        "clone", "--quiet", "--no-local", "--no-hardlinks", "--no-checkout", "--",
        репозиторий.path, клон.path,
      ], at: корень)
    _ = try гит.data(["checkout", "--quiet", "--detach", базовыйКоммит, "--"], at: клон)
    let модули = Data(
      """
      [submodule "independent-project"]
      \tpath = \(путьПроекта)
      \turl = ../project.git
      """.appending("\n").utf8)
    try WritingSubnodePersistence.materialize(
      WritingSubnodeWrite(path: ".gitmodules", contents: модули), cloneURL: клон)
    try WritingSubnodePersistence.materialize(
      WritingSubnodeWrite(
        path: ПредварительнаяПроверкаПроекта.путьРегистрации,
        contents: try регистрация.каноническиеДанные()),
      cloneURL: клон)
    _ = try гит.data(
      ["add", "--", ".gitmodules", ПредварительнаяПроверкаПроекта.путьРегистрации],
      at: клон)
    if обычныйКаталог {
      let вложенныйПуть = "\(путьПроекта)/README.md"
      try WritingSubnodePersistence.materialize(
        WritingSubnodeWrite(path: вложенныйПуть, contents: Data("Обычный каталог\n".utf8)),
        cloneURL: клон)
      _ = try гит.data(["add", "--", вложенныйПуть], at: клон)
    } else {
      _ = try гит.data(
        [
          "update-index", "--add", "--cacheinfo",
          "160000,\(ссылкаПодмодуля),\(путьПроекта)",
        ],
        at: клон)
    }
    let дерево = try гит.text(["write-tree"], at: клон)
    let коммит = try гит.text(
      ["commit-tree", дерево, "-p", базовыйКоммит], at: клон,
      input: Data("Зарегистрировать самостоятельный проект\n".utf8),
      additionalEnvironment: DurableForkValidation.commitEnvironment)
    guard
      try DurableForkValidation.pushCAS(
        newOID: коммит,
        expectedOID: базовыйКоммит,
        ref: "refs/heads/main",
        clone: клон,
        git: гит
      )
    else {
      throw ОшибкаРепозиторияПроекта.подготовка(
        "CAS первоначальной родительской регистрации проигран.")
    }
    return коммит
  }

  fileprivate static func клонироватьВетку(
    голыйРепозиторий: URL,
    в назначение: URL,
    ветка: String,
    гит: CandidateIntegrationGit
  ) throws {
    _ = try гит.data(
      [
        "clone", "--quiet", "--no-local", "--no-hardlinks", "--branch", ветка, "--",
        голыйРепозиторий.path, назначение.path,
      ], at: назначение.deletingLastPathComponent())
  }

  fileprivate static func клонироватьСнимок(
    голыйРепозиторий: URL,
    в назначение: URL,
    коммит: String,
    путьПроекта: String,
    материализовать: Bool,
    гит: CandidateIntegrationGit
  ) throws {
    _ = try гит.data(
      [
        "clone", "--quiet", "--no-local", "--no-hardlinks", "--no-checkout", "--",
        голыйРепозиторий.path, назначение.path,
      ], at: назначение.deletingLastPathComponent())
    _ = try гит.data(["checkout", "--quiet", "--detach", коммит, "--"], at: назначение)
    if материализовать {
      _ = try гит.data(
        ["submodule", "update", "--init", "--", путьПроекта], at: назначение)
    }
  }

  fileprivate static func отчётКомпозиции(
    коммитРодителя: String,
    коммитПроекта: String,
    базовыйКоммитПроекта: String,
    репозиторийРодителя: URL,
    репозиторийПроекта: URL,
    снимокРодителя: URL,
    писатель: URL,
    путьПроекта: String,
    закрытыйДоступ: Bool,
    цикл: Bool
  ) throws -> RepositoryCompositionReport {
    let регистрация = регистрацияПроекта(
      базовыйКоммитПроекта: базовыйКоммитПроекта,
      ссылкаПодмодуля: коммитПроекта,
      путьПроекта: путьПроекта,
      закрытыйДоступ: закрытыйДоступ,
      цикл: цикл)
    let паспорт = RepositoryCompositionPassport(
      schemaVersion: 1,
      passportID: "passport.project-composition.fixture.v1",
      compositionID: "fum.project-composition.fixture.v1",
      parentRepository: RepositoryCompositionParentRepository(
        repositoryID: "repository.parent.fixture",
        repositoryURL: "urn:fum:repository:parent-fixture",
        snapshotOID: коммитРодителя,
        liveRef: "refs/heads/main",
        accessLevel: .public,
        publicationBoundary: .public
      ),
      children: [регистрация.проект]
    )
    let контекст = RepositoryCompositionContext(
      gitExecutableURL: WritingSubnodeSystemRuntime.gitExecutableURL,
      bareRepositoriesByID: [
        "repository.parent.fixture": репозиторийРодителя,
        "repository.project.fixture": репозиторийПроекта,
      ],
      checkoutsByEntryID: [
        "entry.project.fixture": RepositoryCompositionCheckoutContext(
          snapshotURL: снимокРодителя.appending(path: путьПроекта, directoryHint: .isDirectory),
          writerURL: писатель)
      ]
    )
    return RepositoryCompositionPreflight.analyze(
      try DurableForkJSON.encode(паспорт), context: контекст)
  }
}


public enum СхемыДелегированияКонечнойЦепочки {
  public static func загрузитьНазначение() throws -> Data {
    try загрузить(имя: "схема-назначения-конечной-линейной-цепочки-v1")
  }

  public static func загрузитьСостояние() throws -> Data {
    try загрузить(имя: "схема-состояния-конечной-линейной-цепочки-v1")
  }

  private static func загрузить(имя: String) throws -> Data {
    let прямойАдрес = Bundle.module.resourceURL?
      .appendingPathComponent("Фикстуры", isDirectory: true)
      .appendingPathComponent("ДелегированиеКонечнойЦепочки", isDirectory: true)
      .appendingPathComponent(имя)
      .appendingPathExtension("json")
    let адрес =
      (прямойАдрес.flatMap {
        FileManager.default.fileExists(atPath: $0.path) ? $0 : nil
      })
      ?? Bundle.module.url(
        forResource: имя,
        withExtension: "json",
        subdirectory: "Фикстуры/ДелегированиеКонечнойЦепочки"
      )
      ?? Bundle.module.url(
        forResource: имя,
        withExtension: "json",
        subdirectory: "ДелегированиеКонечнойЦепочки"
      )
      ?? Bundle.module.url(forResource: имя, withExtension: "json")
    guard let адрес else {
      throw ОшибкаСхемДелегированияКонечнойЦепочки.ресурсОтсутствует(имя)
    }
    let значения = try адрес.resourceValues(forKeys: [.fileSizeKey])
    guard let размер = значения.fileSize,
      размер <= предельныйРазмерПаспортаКонечнойЦепочки
    else {
      throw ОшибкаСхемДелегированияКонечнойЦепочки.ресурсСлишкомВелик(
        имя,
        значения.fileSize ?? -1
      )
    }
    let данные = try Data(contentsOf: адрес, options: [.mappedIfSafe])
    guard данные.count <= предельныйРазмерПаспортаКонечнойЦепочки else {
      throw ОшибкаСхемДелегированияКонечнойЦепочки.ресурсСлишкомВелик(
        имя,
        данные.count
      )
    }
    return данные
  }
}


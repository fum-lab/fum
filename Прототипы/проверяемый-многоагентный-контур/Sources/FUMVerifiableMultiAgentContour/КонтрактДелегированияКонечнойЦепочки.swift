        нарушения: &нарушения
      )
    }

    let начальнаяЗадача = объект(состояние["начальная_задача_среды"])
    if строка(начальнаяЗадача["идентификатор_физической_рабочей_копии"])
      != строка(назначение["идентификатор_физической_рабочей_копии"])
      || строка(начальнаяЗадача["рабочая_ссылка"]) != рабочаяСсылка

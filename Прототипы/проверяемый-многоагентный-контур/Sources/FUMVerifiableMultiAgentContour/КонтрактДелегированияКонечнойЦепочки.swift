    "результат", "политика_принятия",
  ]

  private static let ключиСостояния: Set<String> = [
    "поколение_схемы", "идентификатор_паспорта", "хэш_состояния",
    "хэш_назначения", "идентификатор_цепочки", "поколение_состояния",
    "исходный_коммит", "текущая_вершина", "идентификатор_физической_рабочей_копии",
    "рабочая_ссылка", "начальная_задача_среды", "эффективные_границы",
    "расход_бюджетов", "шаги", "переходы", "очередь", "состояние_диапазона",
    "внешние_задачи", "принятие", "завершение_без_коммита", "текущий_допуск",
  ]

  public static func проверить(
    назначение данныеНазначения: Data,
    состояние данныеСостояния: Data,
    контекст: КонтекстПроверкиДелегированияКонечнойЦепочки
  ) -> ОтчётПроверкиДелегированияКонечнойЦепочки {
    var нарушения: [НарушениеПроверкиДелегированияКонечнойЦепочки] = []

    guard
      let назначение = разобрать(
        данныеНазначения,
        имя: "назначение",
        нарушения: &нарушения
      ),
      let состояние = разобрать(
        данныеСостояния,
        имя: "состояние",
        нарушения: &нарушения
      )
    else {
      return отчёт(
        идентификаторЦепочки: nil,
        числоШагов: 0,
        состояниеДиапазона: nil,
        текущаяВершина: nil,
        готоваяВершина: nil,
        хэшНазначения: nil,
        нарушения: нарушения
      )
    }

    проверитьСоответствиеОпубликованнымСхемам(
      назначение: назначение,
      состояние: состояние,
      нарушения: &нарушения
    )

    проверитьЗакрытыйОбъект(
      назначение,
      допустимые: ключиНазначения,
      обязательные: ключиНазначения,
      путь: разделительУказателяПаспорта + "назначение",
      нарушения: &нарушения
    )
    проверитьЗакрытыйОбъект(
      состояние,
      допустимые: ключиСостояния,
      обязательные: ключиСостояния.subtracting([
        "завершение_без_коммита", "текущий_допуск",
      ]),
      путь: разделительУказателяПаспорта + "состояние",
      нарушения: &нарушения
    )
    проверитьВложеннуюСтруктуру(
      назначение,
      состояние: состояние,
      нарушения: &нарушения
    )

    if целое(назначение["поколение_схемы"]) != 1
      || целое(состояние["поколение_схемы"]) != 1
    {
      добавить(
        "неподдерживаемое_поколение_схемы",
        путь: "",
        сообщение: "Поддерживается только поколение схемы 1.",
        нарушения: &нарушения
      )
    }

    let идентификаторЦепочки = строка(назначение["идентификатор_цепочки"])
    if строка(состояние["идентификатор_цепочки"]) != идентификаторЦепочки {
      добавить(
        "идентификатор_цепочки_не_совпадает",
        путь: разделительУказателяПаспорта + "состояние/идентификатор_цепочки",
        сообщение: "Состояние относится к другой цепочке.",
        нарушения: &нарушения
      )
    }

    let заявленныйХэшНазначения = строка(назначение["хэш_назначения"])
    let вычисленныйХэшНазначения = хэшОбъекта(
      назначение,
      исключая: "хэш_назначения"
    )
    if заявленныйХэшНазначения == nil
      || заявленныйХэшНазначения != вычисленныйХэшНазначения
    {
      добавить(
        "хэш_назначения_не_совпадает",
        путь: разделительУказателяПаспорта + "назначение/хэш_назначения",
        сообщение: "Хэш назначения не совпадает с каноническим содержимым.",
        нарушения: &нарушения
      )
    }
    if строка(состояние["хэш_назначения"]) != заявленныйХэшНазначения {
      добавить(
        "состояние_ссылается_на_другое_назначение",
        путь: разделительУказателяПаспорта + "состояние/хэш_назначения",
        сообщение: "Паспорт состояния ссылается на другое назначение.",
        нарушения: &нарушения
      )
    }
    if строка(состояние["хэш_состояния"])
      != хэшОбъекта(состояние, исключая: "хэш_состояния")
    {
      добавить(
        "хэш_состояния_не_совпадает",
        путь: разделительУказателяПаспорта + "состояние/хэш_состояния",
        сообщение: "Хэш состояния не совпадает с каноническим содержимым.",
        нарушения: &нарушения
      )
    }

    проверитьТочныеИсточники(
      назначение,
      контекст: контекст,
      нарушения: &нарушения
    )
    проверитьРабочуюЛинию(
      назначение,
      состояние: состояние,
      нарушения: &нарушения
    )
    let карточки = массивОбъектов(назначение["карточки"])
    проверитьЛинейность(карточки, нарушения: &нарушения)
    проверитьРезультат(назначение, карточки: карточки, нарушения: &нарушения)
    проверитьГраницы(
      назначение,
      состояние: состояние,
      нарушения: &нарушения
    )
    проверитьШагиИПереходы(
      назначение,
      состояние: состояние,
      карточки: карточки,
      контекст: контекст,
      нарушения: &нарушения
    )
    проверитьВнешниеЗадачи(состояние, нарушения: &нарушения)

    let состояниеДиапазона = строка(состояние["состояние_диапазона"])
    let вершина = строка(состояние["текущая_вершина"])
    if вершина != контекст.ожидаемаяВершина {
      добавить(
        "вершина_не_совпадает",
        путь: разделительУказателяПаспорта + "состояние/текущая_вершина",
        сообщение: "Фактическая вершина не совпадает с паспортом диапазона.",
        нарушения: &нарушения
      )
    }

    return отчёт(
      идентификаторЦепочки: идентификаторЦепочки,
      числоШагов: карточки.count,
      состояниеДиапазона: состояниеДиапазона,
      текущаяВершина: вершина,
      готоваяВершина: состояниеДиапазона == "готов" ? вершина : nil,
      хэшНазначения: заявленныйХэшНазначения,
      нарушения: нарушения
    )
  }

  private static func проверитьСоответствиеОпубликованнымСхемам(
    назначение: [String: Any],
    состояние: [String: Any],
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let пары: [(String, [String: Any], () throws -> Data)] = [
      ("назначение", назначение, СхемыДелегированияКонечнойЦепочки.загрузитьНазначение),
      ("состояние", состояние, СхемыДелегированияКонечнойЦепочки.загрузитьСостояние),
    ]
    for (имя, документ, загрузить) in пары {
      let данныеСхемы: Data
      do {
        данныеСхемы = try загрузить()
      } catch {
        добавить(
          "схема_контракта_недоступна",
          путь: разделительУказателяПаспорта + "\(имя)",
          сообщение: "Опубликованный ресурс схемы недоступен: \(error)",
          нарушения: &нарушения
        )
        continue
      }
      let нарушенияСхемы = ПроверкаЗакрытойСхемы.проверитьСхему(данныеСхемы)
      for нарушениеСхемы in нарушенияСхемы {
        добавить(
          "схема_контракта_недопустима",
          путь: разделительУказателяПаспорта + "\(имя)/@схема" + нарушениеСхемы.путь,
          сообщение: "\(нарушениеСхемы.код): \(нарушениеСхемы.сообщение)",
          нарушения: &нарушения
        )
      }
      guard нарушенияСхемы.isEmpty else { continue }
      for нарушениеДокумента in ПроверкаЗакрытойСхемы.проверитьДокумент(
        документ,
        по: данныеСхемы
      ) {
        добавить(
          "документ_не_соответствует_схеме",
          путь: разделительУказателяПаспорта + "\(имя)" + нарушениеДокумента.путь,
          сообщение: "\(нарушениеДокумента.код): \(нарушениеДокумента.сообщение)",
          нарушения: &нарушения
        )
      }
    }
  }

  private static func проверитьТочныеИсточники(
    _ назначение: [String: Any],
    контекст: КонтекстПроверкиДелегированияКонечнойЦепочки,
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let карточкаЦепочки = объект(назначение["карточка_цепочки"])
    проверитьЗакрытыйОбъект(

    значение as? [[String: Any]] ?? []
  }

  private static func массивСтрок(_ значение: Any?) -> [String] {
    значение as? [String] ?? []
  }

  private static func строка(_ значение: Any?) -> String? {
    guard let строка = значение as? String, !строка.isEmpty else { return nil }
    return строка
  }

  private static func целое(_ значение: Any?) -> Int? {
    guard let число = значение as? NSNumber,
      CFGetTypeID(число) != CFBooleanGetTypeID()
    else { return nil }
    return Int(число.stringValue)
  }

  private static func полнаяСсылкаВетки(_ значение: String?) -> Bool {
    guard let значение, значение.hasPrefix("refs/heads/"), значение.count <= 1_024
    else { return false }
    let остаток = String(значение.dropFirst("refs/heads/".count))
    guard !остаток.isEmpty, !остаток.hasSuffix("/"), !остаток.hasSuffix("."),
      !остаток.contains("//"), !остаток.contains(".."), !остаток.contains("@{")
    else { return false }
    let запрещённые = CharacterSet.controlCharacters
      .union(.whitespacesAndNewlines)
      .union(CharacterSet(charactersIn: "~^:?*[\\"))
    guard остаток.unicodeScalars.allSatisfy({ !запрещённые.contains($0) }) else {
      return false
    }
    return остаток.split(separator: "/", omittingEmptySubsequences: false).allSatisfy {
      !$0.isEmpty && !$0.hasPrefix(".") && !$0.hasSuffix(".lock")
    }
  }

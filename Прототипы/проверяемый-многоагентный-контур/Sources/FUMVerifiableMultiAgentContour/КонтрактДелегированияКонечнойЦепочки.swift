      )
    }
  }

  private static func проверитьЛинейность(
    _ карточки: [[String: Any]],
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    guard !карточки.isEmpty else {
      добавить(
        "пустая_цепочка",
        путь: разделительУказателяПаспорта + "назначение/карточки",
        сообщение: "Цепочка должна содержать хотя бы одну карточку.",
        нарушения: &нарушения
      )
      return
    }
    let идентификаторы = карточки.compactMap { строка($0["идентификатор"]) }
    if Set(идентификаторы).count != карточки.count {
      добавить(
        "повторная_карточка_в_цепочке",
        путь: разделительУказателяПаспорта + "назначение/карточки",
        сообщение: "Идентификаторы карточек должны быть полными и уникальными.",
        нарушения: &нарушения
      )
    }
    for (индекс, карточка) in карточки.enumerated() {
      if целое(карточка["порядок"]) != индекс + 1 {
        добавить(
          "порядок_карточек_нарушен",
          путь: разделительУказателяПаспорта + "назначение/карточки/\(индекс)/порядок",
          сообщение: "Порядок карточки должен совпадать с её позицией.",
          нарушения: &нарушения
        )
      }
      let зависимости = массивСтрок(карточка["зависит_от"])
      let ожидаемые = индекс == 0 ? [] : [идентификаторы[безопасно: индекс - 1] ?? ""]
      if зависимости != ожидаемые {
        добавить(
          "нелинейный_порядок_зависимостей",
          путь: разделительУказателяПаспорта + "назначение/карточки/\(индекс)/зависит_от",
          сообщение: "Каждая карточка после первой должна зависеть только от предыдущей.",
          нарушения: &нарушения
        )
      }
      if зависимости.contains(идентификаторы[безопасно: индекс] ?? "")
        || зависимости.contains(where: {
          guard let позиция = идентификаторы.firstIndex(of: $0) else { return false }
          return позиция >= индекс
        })
      {
        добавить(
          "цикл_зависимостей",
          путь: разделительУказателяПаспорта + "назначение/карточки/\(индекс)/зависит_от",
          сообщение: "Зависимость ведёт к текущей или следующей карточке.",
          нарушения: &нарушения
        )
      }
    }
  }

  private static func проверитьРезультат(
    _ назначение: [String: Any],
    карточки: [[String: Any]],
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let результат = объект(назначение["результат"])
    let класс = строка(результат["класс"])
    let маршрут = строка(результат["маршрут"])
    let маршруты: [String: String] = [
      "собственный_результат_ребёнка": "в_дочерний_репозиторий",
      "проектный_результат": "в_проект",
      "общий_вклад_в_ядро": "fork_в_ядро",
    ]
    if маршруты[класс ?? ""] != маршрут {
      добавить(
        "неверный_маршрут_результата",
        путь: разделительУказателяПаспорта + "назначение/результат/маршрут",
        сообщение: "Маршрут не соответствует классу результата.",
        нарушения: &нарушения
      )
    }
    if класс == "собственный_результат_ребёнка"
      && строка(результат["целевой_репозиторий"])
        != строка(назначение["идентификатор_репозитория_ребёнка"])
    {
      добавить(
        "неверная_цель_собственного_результата",
        путь: разделительУказателяПаспорта + "назначение/результат/целевой_репозиторий",
        сообщение: "Собственный результат принимается только в репозиторий ребёнка.",
        нарушения: &нарушения
      )
    }
    if класс == "общий_вклад_в_ядро" {
      if let цель = объектИлиОтсутствие(результат["цель_запроса_слияния"]) {
        if строка(цель["идентификатор_репозитория"])
          != строка(результат["целевой_репозиторий"])
          || строка(цель["целевая_ссылка"])
            != строка(результат["целевая_ссылка"])
        {
          добавить(
            "цель_запроса_слияния_не_совпадает_с_маршрутом",
            путь: разделительУказателяПаспорта + "назначение/результат/цель_запроса_слияния",
            сообщение: "Pull request должен вести в ту же точную цель общего результата.",
            нарушения: &нарушения
          )
        }
      } else {
        добавить(
          "цель_запроса_слияния_обязательна",
          путь: разделительУказателяПаспорта + "назначение/результат/цель_запроса_слияния",
          сообщение: "Общий вклад требует точную цель pull request.",
          нарушения: &нарушения
        )
      }
      if результат["кандидат_переносимого_навыка"] as? Bool == nil {
        добавить(
          "признак_кандидата_навыка_обязателен",
          путь: разделительУказателяПаспорта + "назначение/результат/кандидат_переносимого_навыка",
          сообщение: "Общий вклад требует явный признак кандидата навыка.",
          нарушения: &нарушения
        )
      }
    } else if результат["цель_запроса_слияния"] != nil
      || результат["кандидат_переносимого_навыка"] != nil
    {
      добавить(
        "поля_общего_вклада_запрещены",
        путь: разделительУказателяПаспорта + "назначение/результат",
        сообщение: "PR-поля допустимы только для общего вклада в ядро.",
        нарушения: &нарушения
      )
    }

    let политика = объект(назначение["политика_принятия"])
    let режим = строка(политика["режим"])
    if режим == "точный_префикс" {
      let последняя = строка(политика["последняя_карточка"])
      let идентификаторы = карточки.compactMap { строка($0["идентификатор"]) }
      if последняя == nil || !идентификаторы.contains(последняя ?? "") {
        добавить(
          "неверный_точный_префикс",
          путь: разделительУказателяПаспорта + "назначение/политика_принятия/последняя_карточка",
          сообщение: "Точный префикс должен завершаться существующей карточкой цепочки.",
          нарушения: &нарушения
        )
      }
    } else if режим != "вся_цепочка" {
      добавить(
        "неявное_частичное_принятие",
        путь: разделительУказателяПаспорта + "назначение/политика_принятия/режим",
        сообщение: "Версия 1 принимает всю цепочку либо точный именованный префикс.",
        нарушения: &нарушения
      )
    }
  }

  private static func проверитьГраницы(
    _ назначение: [String: Any],
    состояние: [String: Any],
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let выданные = объект(назначение["границы"])
    let эффективные = объект(состояние["эффективные_границы"])
    let поляПодмножеств = ["области", "инструменты", "внешние_эффекты", "терминальные_исходы"]
    for поле in поляПодмножеств {
      let исходные = Set(массивСтрок(выданные[поле]))
      let фактические = Set(массивСтрок(эффективные[поле]))
      if !фактические.isSubset(of: исходные) {
        добавить(
          "расширение_границ_ребёнком",
          путь: разделительУказателяПаспорта + "состояние/эффективные_границы/\(поле)",
          сообщение: "Эффективная граница расширяет выданное множество.",
          нарушения: &нарушения
        )
      }
    }
    let исходныеИсключения = Set(массивСтрок(выданные["исключения"]))
    let эффективныеИсключения = Set(массивСтрок(эффективные["исключения"]))
    if !исходныеИсключения.isSubset(of: эффективныеИсключения) {
      добавить(
        "расширение_границ_ребёнком",
        путь: разделительУказателяПаспорта + "состояние/эффективные_границы/исключения",
        сообщение: "Ребёнок не может снять выданное исключение.",
        нарушения: &нарушения
      )
    }

    let уровни = ["публичный", "ограниченный", "приватный", "закрытый"]
    let выданныйУровень = уровни.firstIndex(of: строка(выданные["уровень_доступа"]) ?? "")
    let эффективныйУровень = уровни.firstIndex(of: строка(эффективные["уровень_доступа"]) ?? "")
    if выданныйУровень == nil || эффективныйУровень == nil {
      добавить(
        "неизвестный_уровень_доступа",
        путь: разделительУказателяПаспорта + "состояние/эффективные_границы/уровень_доступа",
        сообщение: "Уровень доступа должен входить в закрытый перечень.",
        нарушения: &нарушения
      )
    } else if let выданныйУровень, let эффективныйУровень,
      эффективныйУровень > выданныйУровень
    {
      добавить(
        "расширение_границ_ребёнком",
        путь: разделительУказателяПаспорта + "состояние/эффективные_границы/уровень_доступа",
        сообщение: "Эффективный уровень доступа сильнее выданного.",
        нарушения: &нарушения
      )
    }

    for поле in ["параллелизм", "глубина_рекурсии"] {
      let выданное = целое(выданные[поле])
      let эффективное = целое(эффективные[поле])
      if выданное == nil || эффективное == nil || (эффективное ?? 0) < 0 {
        добавить(
          "неверная_числовая_граница",
          путь: разделительУказателяПаспорта + "состояние/эффективные_границы/\(поле)",
          сообщение: "Числовая граница должна быть неотрицательным целым числом.",
          нарушения: &нарушения
        )
      } else if (эффективное ?? 0) > (выданное ?? 0) {
        добавить(
          "расширение_границ_ребёнком",
          путь: разделительУказателяПаспорта + "состояние/эффективные_границы/\(поле)",
          сообщение: "Эффективный числовой предел превышает выданный.",
          нарушения: &нарушения
        )
      }
    }

    let бюджеты = объект(выданные["бюджеты"])
    let расход = объект(состояние["расход_бюджетов"])
    for поле in ["токены", "секунды", "изменённые_файлы"] {
      let предел = целое(бюджеты[поле])
      let значение = целое(расход[поле])
      if предел == nil || значение == nil || (предел ?? 0) < 0 || (значение ?? 0) < 0 {
        добавить(
          "неверное_значение_бюджета",
          путь: разделительУказателяПаспорта + "состояние/расход_бюджетов/\(поле)",
          сообщение: "Бюджет и расход должны быть неотрицательными целыми числами.",
          нарушения: &нарушения
        )
      } else if (значение ?? 0) > (предел ?? 0) {
        добавить(
          "бюджет_превышен",
          путь: разделительУказателяПаспорта + "состояние/расход_бюджетов/\(поле)",
          сообщение: "Совокупный расход превышает бюджет назначения.",
          нарушения: &нарушения
        )
      }
    }
  }

  private static func проверитьШагиИПереходы(
    _ назначение: [String: Any],
    состояние: [String: Any],
    карточки: [[String: Any]],
    контекст: КонтекстПроверкиДелегированияКонечнойЦепочки,
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let шаги = массивОбъектов(состояние["шаги"])
    let переходы = массивОбъектов(состояние["переходы"])
    let идентификаторРабочейКопии = строка(
      назначение["идентификатор_физической_рабочей_копии"]
    )
    let рабочаяСсылка = строка(назначение["рабочая_ссылка"])
    let исходнаяВершина = строка(назначение["исходный_коммит"])
    let начальнаяЗадача = объект(состояние["начальная_задача_среды"])
    let эффективныеИсходы = Set(
      массивСтрок(объект(состояние["эффективные_границы"])["терминальные_исходы"])
    )

    if шаги.count != карточки.count {
      добавить(
        "список_шагов_не_совпадает",
        путь: разделительУказателяПаспорта + "состояние/шаги",
        сообщение: "Паспорт должен представить каждую карточку цепочки ровно одним шагом.",
        нарушения: &нарушения
      )
    }
    if переходы.count > карточки.count {
      добавить(
        "переходы_не_образуют_префикс",
        путь: разделительУказателяПаспорта + "состояние/переходы",
        сообщение: "Число переходов не может превышать число карточек.",
        нарушения: &нарушения
      )
    }
    if переходы.count != контекст.связанныеКоммиты.count {
      добавить(
        "свидетельство_связанного_коммита_отсутствует",
        путь: разделительУказателяПаспорта + "состояние/переходы",
        сообщение: "Каждому заявленному переходу нужно ровно одно авторитетное свидетельство.",
        нарушения: &нарушения
      )
    }
    if !переходы.isEmpty && !эффективныеИсходы.contains("committed") {
      добавить(
        "коммит_не_разрешён_эффективными_границами",
        путь: разделительУказателяПаспорта + "состояние/эффективные_границы/терминальные_исходы",
        сообщение: "Суженные границы должны явно разрешать каждый committed-переход.",
        нарушения: &нарушения
      )
    }

    var предыдущаяВершина = исходнаяВершина
    var предыдущийПорядокДопуска = 0
    var предыдущийНомерВладельца = 0
    var предыдущийНомерПродолжения = 0
    var билетыВладельцев: Set<String> = []
    var билетыПродолжений: Set<String> = []
    var задачиВладельцев: Set<String> = []
    var задачиПродолжений: Set<String> = []
    var хэшиДопусков: Set<String> = []
    var хэшиКвитанций: Set<String> = []
    var хэшиСвязанныхКоммитов: Set<String> = []
    var поколенияДопусков: Set<String> = []
    var идентичностиПоЗадаче: [String: ИдентичностьБилетаКонечнойЦепочки] = [:]
    var идентичностиПоБилету: [String: ИдентичностьБилетаКонечнойЦепочки] = [:]
    var идентичностиПоНомеру: [Int: ИдентичностьБилетаКонечнойЦепочки] = [:]
    var ожидающиеПродолженияПоНомеру: [Int: ИдентичностьБилетаКонечнойЦепочки] = [:]
    for (индекс, переход) in переходы.enumerated() {
      let ожидаемаяКарточка = карточки[безопасно: индекс]
      if целое(переход["порядок"]) != индекс + 1
        || строка(переход["идентификатор_карточки"])
          != строка(ожидаемаяКарточка?["идентификатор"])
      {
        добавить(
          "переход_не_совпадает_с_карточкой",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)",
          сообщение: "Переход должен совпадать с той же позицией карточки назначения.",
          нарушения: &нарушения
        )
      }
      if строка(переход["входная_вершина"]) != предыдущаяВершина {
        добавить(
          "разрыв_линейного_диапазона",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/входная_вершина",
          сообщение: "Переход не продолжает предыдущую вершину.",
          нарушения: &нарушения
        )
      }
      if целое(переход["число_родителей"]) != 1 {
        добавить(
          "коммит_слияния_в_цепочке",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/число_родителей",
          сообщение: "Внутри линейной цепочки допустим только один родитель.",
          нарушения: &нарушения
        )
      }
      if строка(переход["коммит"]) == строка(переход["входная_вершина"]) {
        добавить(
          "пустой_переход_коммита",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/коммит",
          сообщение: "Выходной коммит должен отличаться от входной вершины.",
          нарушения: &нарушения
        )
      }

      let продолжение = объектИлиОтсутствие(переход["продолжение"])
      guard let продолжение else {
        добавить(
          "продолжение_отсутствует",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/продолжение",
          сообщение: "Осмысленный commit должен ссылаться на одно продолжение.",
          нарушения: &нарушения
        )
        предыдущаяВершина = строка(переход["коммит"])
        continue
      }

      let задачаВладельца = строка(переход["задача_владельца"])
      let задачаПродолжения = строка(продолжение["идентификатор_задачи"])
      if индекс == 0
        && задачаВладельца != строка(начальнаяЗадача["идентификатор_задачи"])
      {
        добавить(
          "начальная_задача_не_является_первым_владельцем",
          путь: разделительУказателяПаспорта + "состояние/переходы/0/задача_владельца",
          сообщение: "Первый переход принадлежит начальной задаче среды.",
          нарушения: &нарушения
        )
      }

      if задачаПродолжения == задачаВладельца {
        добавить(
          "продолжение_совпадает_с_владельцем",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/продолжение/идентификатор_задачи",
          сообщение: "Продолжение должно быть новой задачей, отличной от владельца.",
          нарушения: &нарушения
        )
      }
      if строка(продолжение["идентификатор_физической_рабочей_копии"])
        != идентификаторРабочейКопии
      {
        добавить(
          "рабочая_копия_продолжения_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/продолжение",
          сообщение: "Продолжение создано в другой физической рабочей копии.",
          нарушения: &нарушения
        )
      }
      if строка(продолжение["рабочая_ссылка"]) != рабочаяСсылка {
        добавить(
          "рабочая_ссылка_продолжения_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/продолжение",
          сообщение: "Продолжение создано для другой рабочей ссылки.",
          нарушения: &нарушения
        )
      }
      if строка(продолжение["подтверждённая_вершина"])
        != строка(переход["входная_вершина"])
      {
        добавить(
          "подтверждённая_вершина_продолжения_не_совпадает",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/продолжение/подтверждённая_вершина",
          сообщение: "Продолжение должно подтвердить входную вершину владельца.",
          нарушения: &нарушения
        )
      }

      let допуск = объект(переход["допуск_владельца"])
      if let поколение = строка(допуск["поколение_очереди"]),
        !поколенияДопусков.insert(поколение).inserted
      {
        добавить(
          "повтор_поколения_допуска",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/допуск_владельца/поколение_очереди",
          сообщение: "Поколение владения FIFO нельзя повторно использовать для другого шага.",
          нарушения: &нарушения
        )
      }
      if let хэш = строка(допуск["хэш_свидетельства"]),
        !хэшиДопусков.insert(хэш).inserted
      {
        добавить(
          "повтор_свидетельства_допуска",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/допуск_владельца/хэш_свидетельства",
          сообщение: "Одно свидетельство допуска не может подтверждать два перехода.",
          нарушения: &нарушения
        )
      }
      if let хэш = строка(переход["хэш_квитанции"]),
        !хэшиКвитанций.insert(хэш).inserted
      {
        добавить(
          "повтор_квитанции_связанного_коммита",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/хэш_квитанции",
          сообщение: "Одна квитанция не может связывать два разных коммита.",
          нарушения: &нарушения
        )
      }
      if let хэш = строка(переход["хэш_свидетельства_связанного_коммита"]),
        !хэшиСвязанныхКоммитов.insert(хэш).inserted
      {
        добавить(
          "повтор_свидетельства_связанного_коммита",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/хэш_свидетельства_связанного_коммита",
          сообщение: "Одно свидетельство не может описывать два разных связанных коммита.",
          нарушения: &нарушения
        )
      }
      if строка(допуск["идентификатор_эпохи_очереди"])
        != контекст.снимокОчереди.идентификаторЭпохиОчереди
      {
        добавить(
          "эпоха_очереди_изменилась",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/допуск_владельца/идентификатор_эпохи_очереди",
          сообщение: "Допуск перехода относится к другой эпохе branch-scoped FIFO.",
          нарушения: &нарушения
        )
      }
      let порядокДопуска = целое(допуск["порядок_допуска"])
      if let порядокДопуска, порядокДопуска <= предыдущийПорядокДопуска {
        добавить(
          "порядок_допусков_нарушен",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/допуск_владельца/порядок_допуска",
          сообщение: "Переходы должны следовать возрастанию авторитетных допусков.",
          нарушения: &нарушения
        )
      }
      if let порядокДопуска { предыдущийПорядокДопуска = порядокДопуска }
      let номерВладельца = целое(допуск["порядковый_номер_билета"])
      let номерПродолжения = целое(продолжение["порядковый_номер_билета"])
      if let номерВладельца, номерВладельца <= предыдущийНомерВладельца {
        добавить(
          "порядок_номеров_владельцев_нарушен",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/допуск_владельца/порядковый_номер_билета",
          сообщение: "Последовательные допуски владельцев должны иметь возрастающие FIFO seq.",
          нарушения: &нарушения
        )
      }
      if let номерПродолжения,
        номерПродолжения <= предыдущийНомерПродолжения
      {
        добавить(
          "порядок_номеров_продолжений_нарушен",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/продолжение/порядковый_номер_билета",
          сообщение: "Последовательно создаваемые продолжения должны иметь возрастающие FIFO seq.",
          нарушения: &нарушения
        )
      }
      if let номерВладельца { предыдущийНомерВладельца = номерВладельца }
      if let номерПродолжения { предыдущийНомерПродолжения = номерПродолжения }
      if let номерВладельца, let номерПродолжения,
        номерПродолжения <= номерВладельца
      {
        добавить(
          "обход_очереди",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/продолжение/порядковый_номер_билета",
          сообщение: "Ожидающий билет продолжения должен следовать после билета владельца.",
          нарушения: &нарушения
        )
      }
      if строка(допуск["базовая_вершина"])
        != строка(переход["входная_вершина"])
      {
        добавить(
          "свидетельство_допуска_не_совпадает",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/допуск_владельца/базовая_вершина",
          сообщение: "Допуск владельца должен быть закреплён за входной вершиной.",
          нарушения: &нарушения
        )
      }

      let билетВладельца = строка(допуск["идентификатор_билета"])
      let билетПродолжения = строка(продолжение["идентификатор_билета"])
      if let задачаВладельца, let билетВладельца, let номерВладельца {
        let идентичностьВладельца = ИдентичностьБилетаКонечнойЦепочки(
          задача: задачаВладельца,
          билет: билетВладельца,
          номер: номерВладельца
        )
        проверитьДопускБезОбходаОжидающихПродолжений(
          идентичностьВладельца,
          ожидающие: &ожидающиеПродолженияПоНомеру,
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/допуск_владельца",
          нарушения: &нарушения
        )
        зарегистрироватьИдентичностьБилета(
          идентичностьВладельца,
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/допуск_владельца",
          поЗадаче: &идентичностиПоЗадаче,
          поБилету: &идентичностиПоБилету,
          поНомеру: &идентичностиПоНомеру,
          нарушения: &нарушения
        )
      }
      if билетПродолжения == билетВладельца
        || билетПродолжения.map({ билетыВладельцев.contains($0) }) == true
        || номерПродолжения.map({ идентичностиПоНомеру[$0] != nil }) == true
      {
        добавить(
          "повтор_идентичности_билета",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/продолжение/идентификатор_билета",
          сообщение: "Новая задача продолжения не может повторять уже владевший билет.",
          нарушения: &нарушения
        )
      }
      if задачаПродолжения == задачаВладельца
        || задачаПродолжения.map({ задачиВладельцев.contains($0) }) == true
      {
        добавить(
          "продолжение_повторяет_задачу_владельца",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/продолжение/идентификатор_задачи",
          сообщение: "Новая задача продолжения не может повторять уже владевшую задачу.",
          нарушения: &нарушения
        )
      }
      if let билетВладельца, !билетыВладельцев.insert(билетВладельца).inserted {
        добавить(
          "повтор_идентичности_билета",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/допуск_владельца/идентификатор_билета",
          сообщение: "Один допущенный билет не может владеть двумя переходами.",
          нарушения: &нарушения
        )
      }
      if let билетПродолжения,
        !билетыПродолжений.insert(билетПродолжения).inserted
      {
        добавить(
          "повтор_идентичности_билета",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/продолжение/идентификатор_билета",
          сообщение: "Один ожидающий билет не может быть продолжением двух коммитов.",
          нарушения: &нарушения
        )
      }
      if let задачаВладельца, !задачиВладельцев.insert(задачаВладельца).inserted {
        добавить(
          "повтор_задачи_владельца",
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/задача_владельца",
          сообщение: "Одна задача не может коммитить два шага цепочки.",
          нарушения: &нарушения
        )
      }
      if let задачаПродолжения,
        !задачиПродолжений.insert(задачаПродолжения).inserted
      {
        добавить(
          "продолжение_дублировано",
          путь: разделительУказателяПаспорта
            + "состояние/переходы/\(индекс)/продолжение/идентификатор_задачи",
          сообщение: "Одна задача не может быть продолжением двух коммитов.",
          нарушения: &нарушения
        )
      }
      if let задачаПродолжения, let билетПродолжения, let номерПродолжения {
        let идентичность = ИдентичностьБилетаКонечнойЦепочки(
          задача: задачаПродолжения,
          билет: билетПродолжения,
          номер: номерПродолжения
        )
        зарегистрироватьИдентичностьБилета(
          идентичность,
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)/продолжение",
          поЗадаче: &идентичностиПоЗадаче,
          поБилету: &идентичностиПоБилету,
          поНомеру: &идентичностиПоНомеру,
          нарушения: &нарушения
        )
        if ожидающиеПродолженияПоНомеру[номерПродолжения] == nil {
          ожидающиеПродолженияПоНомеру[номерПродолжения] = идентичность
        }
      }

      if let свидетельство = контекст.связанныеКоммиты[безопасно: индекс] {
        проверитьСвидетельствоСвязанногоКоммита(
          свидетельство,
          переход: переход,
          продолжение: продолжение,
          рабочаяКопия: идентификаторРабочейКопии,
          рабочаяСсылка: рабочаяСсылка,
          путь: разделительУказателяПаспорта + "состояние/переходы/\(индекс)",
          нарушения: &нарушения
        )
      }
      предыдущаяВершина = строка(переход["коммит"])
    }

    let состояниеДиапазона = строка(состояние["состояние_диапазона"])
    let требуетЗавершениеБезКоммита = [
      "остановлен", "завершён_без_коммита", "отклонён",
    ].contains(состояниеДиапазона ?? "")
    let текущийШаг = шаги[безопасно: переходы.count]
    let требуетТекущийДопуск =
      состояниеДиапазона == "в_работе"
      && строка(текущийШаг?["состояние"]) == "в_работе"
    let текущийДопуск = объектИлиОтсутствие(состояние["текущий_допуск"])
    let завершениеБезКоммита = объектИлиОтсутствие(
      состояние["завершение_без_коммита"]
    )
    var итоговыйПорядокДопуска = предыдущийПорядокДопуска
    if требуетТекущийДопуск {
      guard let текущийДопуск, let свидетельство = контекст.текущийДопуск else {
        добавить(
          "свидетельство_текущего_допуска_отсутствует",
          путь: разделительУказателяПаспорта + "состояние/текущий_допуск",
          сообщение: "Шаг в работе требует авторитетный допуск текущего владельца.",
          нарушения: &нарушения
        )
        return
      }
      let индекс = переходы.count
      let карточка = карточки[безопасно: индекс]
      let допуск = объект(текущийДопуск["допуск_владельца"])
      let задача = строка(текущийДопуск["задача_владельца"])
      let порядокДопуска = целое(допуск["порядок_допуска"])
      let номерБилета = целое(допуск["порядковый_номер_билета"])
      let билет = строка(допуск["идентификатор_билета"])
      if переходы.isEmpty
        && задача != строка(начальнаяЗадача["идентификатор_задачи"])
      {
        добавить(
          "начальная_задача_не_является_первым_владельцем",
          путь: разделительУказателяПаспорта + "состояние/текущий_допуск/задача_владельца",
          сообщение: "Первый активный шаг принадлежит начальной задаче среды.",
          нарушения: &нарушения
        )
      }
      if целое(текущийДопуск["порядок"]) != индекс + 1
        || строка(текущийДопуск["идентификатор_карточки"])
          != строка(карточка?["идентификатор"])
        || строка(текущийДопуск["текущая_вершина"]) != предыдущаяВершина
        || строка(текущийДопуск["идентификатор_физической_рабочей_копии"])
          != идентификаторРабочейКопии
        || строка(текущийДопуск["рабочая_ссылка"]) != рабочаяСсылка
        || порядокДопуска == nil || порядокДопуска ?? 0 <= предыдущийПорядокДопуска
        || номерБилета == nil || номерБилета ?? 0 <= предыдущийНомерВладельца
        || строка(допуск["идентификатор_эпохи_очереди"])
          != контекст.снимокОчереди.идентификаторЭпохиОчереди
        || строка(допуск["базовая_вершина"]) != предыдущаяВершина
      {
        добавить(
          "текущий_допуск_не_совпадает_с_префиксом",
          путь: разделительУказателяПаспорта + "состояние/текущий_допуск",
          сообщение: "Активный допуск должен продолжать точный commit-префикс и FIFO.",
          нарушения: &нарушения
        )
      }
      if свидетельство.идентификаторЗадачи != задача
        || свидетельство.порядокДопуска != порядокДопуска
        || свидетельство.идентификаторЭпохиОчереди
          != строка(допуск["идентификатор_эпохи_очереди"])
        || свидетельство.идентификаторБилета != билет
        || свидетельство.порядковыйНомерБилета != номерБилета
        || свидетельство.поколениеОчереди != строка(допуск["поколение_очереди"])
        || свидетельство.базоваяВершина != строка(допуск["базовая_вершина"])
        || свидетельство.хэшСвидетельства != строка(допуск["хэш_свидетельства"])
      {
        добавить(
          "свидетельство_текущего_допуска_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/текущий_допуск/допуск_владельца",
          сообщение: "Заявленный активный допуск не совпадает с доверенным контекстом.",
          нарушения: &нарушения
        )
      }
      if let хэш = строка(допуск["хэш_свидетельства"]),
        !хэшиДопусков.insert(хэш).inserted
      {
        добавить(
          "повтор_свидетельства_допуска",
          путь: разделительУказателяПаспорта
            + "состояние/текущий_допуск/допуск_владельца/хэш_свидетельства",
          сообщение: "Активный шаг требует отдельное свидетельство допуска.",
          нарушения: &нарушения
        )
      }
      if let поколение = строка(допуск["поколение_очереди"]),
        !поколенияДопусков.insert(поколение).inserted
      {
        добавить(
          "повтор_поколения_допуска",
          путь: разделительУказателяПаспорта
            + "состояние/текущий_допуск/допуск_владельца/поколение_очереди",
          сообщение: "Активный владелец требует новое поколение FIFO.",
          нарушения: &нарушения
        )
      }
      if let задача, let билет, let номерБилета {
        let идентичность = ИдентичностьБилетаКонечнойЦепочки(
          задача: задача,
          билет: билет,
          номер: номерБилета
        )
        проверитьДопускБезОбходаОжидающихПродолжений(
          идентичность,
          ожидающие: &ожидающиеПродолженияПоНомеру,
          путь: разделительУказателяПаспорта + "состояние/текущий_допуск/допуск_владельца",
          нарушения: &нарушения
        )
        зарегистрироватьИдентичностьБилета(
          идентичность,
          путь: разделительУказателяПаспорта + "состояние/текущий_допуск/допуск_владельца",
          поЗадаче: &идентичностиПоЗадаче,
          поБилету: &идентичностиПоБилету,
          поНомеру: &идентичностиПоНомеру,
          нарушения: &нарушения
        )
      }
      итоговыйПорядокДопуска = порядокДопуска ?? итоговыйПорядокДопуска
    } else if текущийДопуск != nil || контекст.текущийДопуск != nil {
      добавить(
        "лишнее_свидетельство_текущего_допуска",
        путь: разделительУказателяПаспорта + "состояние/текущий_допуск",
        сообщение: "Текущий допуск разрешён только для шага со статусом в_работе.",
        нарушения: &нарушения
      )
    }
    if требуетЗавершениеБезКоммита {
      guard let завершениеБезКоммита,
        let свидетельство = контекст.завершениеБезКоммита
      else {
        добавить(
          "свидетельство_завершения_без_коммита_отсутствует",
          путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита",
          сообщение: "Отрицательный префикс требует авторитетное свидетельство finish-clean.",
          нарушения: &нарушения
        )
        return
      }
      let индекс = переходы.count
      let карточка = карточки[безопасно: индекс]
      let шаг = шаги[безопасно: индекс]
      let допуск = объект(завершениеБезКоммита["допуск_владельца"])
      let задача = строка(завершениеБезКоммита["задача_владельца"])
      let порядокДопуска = целое(допуск["порядок_допуска"])
      let номерБилета = целое(допуск["порядковый_номер_билета"])
      let билет = строка(допуск["идентификатор_билета"])
      let ожидаемыйИсход = строка(шаг?["терминальный_исход"])
      if let поколение = строка(допуск["поколение_очереди"]),
        !поколенияДопусков.insert(поколение).inserted
      {
        добавить(
          "повтор_поколения_допуска",
          путь: разделительУказателяПаспорта
            + "состояние/завершение_без_коммита/допуск_владельца/поколение_очереди",
          сообщение: "Finish-clean должен принадлежать новому поколению владения FIFO.",
          нарушения: &нарушения
        )
      }
      if переходы.isEmpty
        && задача != строка(начальнаяЗадача["идентификатор_задачи"])
      {
        добавить(
          "начальная_задача_не_является_первым_владельцем",
          путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита/задача_владельца",
          сообщение: "Первый шаг без коммита также принадлежит начальной задаче среды.",
          нарушения: &нарушения
        )
      }
      if let хэш = строка(допуск["хэш_свидетельства"]),
        !хэшиДопусков.insert(хэш).inserted
      {
        добавить(
          "повтор_свидетельства_допуска",
          путь: разделительУказателяПаспорта
            + "состояние/завершение_без_коммита/допуск_владельца/хэш_свидетельства",
          сообщение: "Finish-clean не может повторно использовать свидетельство прошлого допуска.",
          нарушения: &нарушения
        )
      }
      if целое(завершениеБезКоммита["порядок"]) != индекс + 1
        || строка(завершениеБезКоммита["идентификатор_карточки"])
          != строка(карточка?["идентификатор"])
        || строка(завершениеБезКоммита["текущая_вершина"]) != предыдущаяВершина
        || строка(завершениеБезКоммита["идентификатор_физической_рабочей_копии"])
          != идентификаторРабочейКопии
        || строка(завершениеБезКоммита["рабочая_ссылка"]) != рабочаяСсылка
        || строка(завершениеБезКоммита["терминальный_исход"]) != ожидаемыйИсход
      {
        добавить(
          "завершение_без_коммита_не_совпадает_с_префиксом",
          путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита",
          сообщение: "Finish-clean должен относиться к точному текущему шагу и рабочей линии.",
          нарушения: &нарушения
        )
      }
      if порядокДопуска == nil || порядокДопуска ?? 0 <= предыдущийПорядокДопуска
        || номерБилета == nil || номерБилета ?? 0 <= предыдущийНомерВладельца
        || строка(допуск["идентификатор_эпохи_очереди"])
          != контекст.снимокОчереди.идентификаторЭпохиОчереди
        || строка(допуск["базовая_вершина"]) != предыдущаяВершина
      {
        добавить(
          "допуск_завершения_без_коммита_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита/допуск_владельца",
          сообщение:
            "Отрицательный исход должен принадлежать следующему авторитетному допуску FIFO.",
          нарушения: &нарушения
        )
      }
      if let задача, задачиВладельцев.contains(задача) {
        добавить(
          "повтор_задачи_владельца",
          путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита/задача_владельца",
          сообщение: "Ранее завершившая commit задача не может повторно владеть текущим шагом.",
          нарушения: &нарушения
        )
      }
      if let задача, let билет, let номерБилета {
        let идентичность = ИдентичностьБилетаКонечнойЦепочки(
          задача: задача,
          билет: билет,
          номер: номерБилета
        )
        проверитьДопускБезОбходаОжидающихПродолжений(
          идентичность,
          ожидающие: &ожидающиеПродолженияПоНомеру,
          путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита/допуск_владельца",
          нарушения: &нарушения
        )
        зарегистрироватьИдентичностьБилета(
          идентичность,
          путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита/допуск_владельца",
          поЗадаче: &идентичностиПоЗадаче,
          поБилету: &идентичностиПоБилету,
          поНомеру: &идентичностиПоНомеру,
          нарушения: &нарушения
        )
      }
      if свидетельство.порядокШага != целое(завершениеБезКоммита["порядок"])
        || свидетельство.идентификаторКарточки
          != строка(завершениеБезКоммита["идентификатор_карточки"])
        || свидетельство.идентификаторЧастногоПаспорта
          != строка(объект(шаг?["частный_паспорт"])["идентификатор"])
        || свидетельство.путьЧастногоПаспорта
          != строка(объект(шаг?["частный_паспорт"])["путь"])
        || свидетельство.хэшЧастногоПаспорта
          != строка(объект(шаг?["частный_паспорт"])["хэш"])
        || свидетельство.допускВладельца.идентификаторЗадачи != задача
        || свидетельство.допускВладельца.порядокДопуска != порядокДопуска
        || свидетельство.допускВладельца.идентификаторЭпохиОчереди
          != строка(допуск["идентификатор_эпохи_очереди"])
        || свидетельство.допускВладельца.идентификаторБилета != билет
        || свидетельство.допускВладельца.порядковыйНомерБилета != номерБилета
        || свидетельство.допускВладельца.поколениеОчереди
          != строка(допуск["поколение_очереди"])
        || свидетельство.допускВладельца.базоваяВершина
          != строка(допуск["базовая_вершина"])
        || свидетельство.допускВладельца.хэшСвидетельства
          != строка(допуск["хэш_свидетельства"])
        || свидетельство.идентификаторФизическойРабочейКопии
          != идентификаторРабочейКопии
        || свидетельство.рабочаяСсылка != рабочаяСсылка
        || свидетельство.текущаяВершина != предыдущаяВершина
        || свидетельство.терминальныйИсход != ожидаемыйИсход
        || свидетельство.хэшСвидетельства
          != строка(завершениеБезКоммита["хэш_свидетельства"])
      {
        добавить(
          "свидетельство_завершения_без_коммита_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита",
          сообщение: "Представленный finish-clean не совпадает с доверенным контекстом.",
          нарушения: &нарушения
        )
      }
      итоговыйПорядокДопуска = порядокДопуска ?? итоговыйПорядокДопуска
    } else if завершениеБезКоммита != nil || контекст.завершениеБезКоммита != nil {
      добавить(
        "лишнее_свидетельство_завершения_без_коммита",
        путь: разделительУказателяПаспорта + "состояние/завершение_без_коммита",
        сообщение: "Commit-префикс не должен содержать свидетельство finish-clean.",
        нарушения: &нарушения
      )
    }

    if строка(состояние["текущая_вершина"]) != предыдущаяВершина {
      добавить(
        "текущая_вершина_не_совпадает_с_префиксом",
        путь: разделительУказателяПаспорта + "состояние/текущая_вершина",
        сообщение: "Текущая вершина должна завершать точный префикс переходов.",
        нарушения: &нарушения
      )
    }

    var суммарныйРасход = [
      "токены": 0,
      "секунды": 0,
      "изменённые_файлы": 0,
    ]
    var переполнениеРасхода = false
    var успешныеПроверки: Set<String> = []
    for (индекс, шаг) in шаги.enumerated() {
      if целое(шаг["порядок"]) != индекс + 1
        || строка(шаг["идентификатор_карточки"])
          != строка(карточки[безопасно: индекс]?["идентификатор"])
      {
        добавить(
          "шаг_не_совпадает_с_карточкой",
          путь: разделительУказателяПаспорта + "состояние/шаги/\(индекс)",
          сообщение: "Состояние шага нарушает порядок назначения.",
          нарушения: &нарушения
        )
      }
      if строка(шаг["хэш_карточки"])
        != строка(карточки[безопасно: индекс]?["хэш_содержимого"])
      {
        добавить(
          "хэш_карточки_шага_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/шаги/\(индекс)/хэш_карточки",
          сообщение: "Шаг должен ссылаться на точный хэш карточки назначения.",
          нарушения: &нарушения
        )
      }

      let фактическоеСостояние = строка(шаг["состояние"])
      let ожидаемыеСостояния: Set<String>
      if индекс < переходы.count {
        ожидаемыеСостояния = ["завершён"]
      } else if индекс > переходы.count {
        ожидаемыеСостояния = ["ожидает"]
      } else if переходы.count == карточки.count {
        ожидаемыеСостояния = []
      } else {
        switch состояниеДиапазона {
        case "назначен": ожидаемыеСостояния = ["ожидает"]
        case "в_работе": ожидаемыеСостояния = ["ожидает", "в_работе"]
        case "остановлен", "завершён_без_коммита":
          ожидаемыеСостояния = ["остановлен"]
        case "отклонён": ожидаемыеСостояния = ["отклонён"]
        default: ожидаемыеСостояния = []
        }
      }
      if let фактическоеСостояние,
        !ожидаемыеСостояния.contains(фактическоеСостояние)
      {
        добавить(
          "состояния_шагов_не_образуют_префикс",
          путь: разделительУказателяПаспорта + "состояние/шаги/\(индекс)/состояние",
          сообщение: "Состояния шагов должны образовывать завершённый префикс и один текущий шаг.",
          нарушения: &нарушения
        )
      }

      if фактическоеСостояние == "завершён" {
        let расход = объект(шаг["расход_бюджетов"])
        let проверки = массивОбъектов(шаг["проверки"])
        let паспорт = объект(шаг["частный_паспорт"])
        if расход.isEmpty || проверки.isEmpty
          || строка(паспорт["вид"]) != "рабочий_пакет"
        {
          добавить(
            "свидетельства_завершённого_шага_неполны",
            путь: разделительУказателяПаспорта + "состояние/шаги/\(индекс)",
            сообщение: "Завершённый шаг должен связать расход бюджета и проверки.",
            нарушения: &нарушения
          )
        }
        if проверки.contains(where: { строка($0["исход"]) != "успешно" }) {
          добавить(
            "проверка_шага_неуспешна",
            путь: разделительУказателяПаспорта + "состояние/шаги/\(индекс)/проверки",
            сообщение: "Готовый диапазон не может содержать неуспешную проверку шага.",
            нарушения: &нарушения
          )
        }
        for проверка in проверки
        where строка(проверка["исход"]) == "успешно" {
          if let идентификатор = строка(проверка["идентификатор"]) {
            успешныеПроверки.insert(идентификатор)
          }
        }
      }

      if фактическоеСостояние == "остановлен" || фактическоеСостояние == "отклонён" {
        let паспорт = объект(шаг["частный_паспорт"])
        let терминальныйИсход = строка(шаг["терминальный_исход"])
        let ожидаемыйИсход: String? =
          состояниеДиапазона == "отклонён" ? "failed" : "finished_clean"
        if строка(паспорт["вид"]) != "отрицательный_исход"
          || терминальныйИсход == nil
          || !эффективныеИсходы.contains(терминальныйИсход ?? "")
          || терминальныйИсход != ожидаемыйИсход
          || объектИлиОтсутствие(шаг["расход_бюджетов"]) == nil
        {
          добавить(
            "отрицательный_исход_не_типизирован",
            путь: разделительУказателяПаспорта + "состояние/шаги/\(индекс)",
            сообщение: "Шаг без коммита требует разрешённый терминальный исход, паспорт и расход.",
            нарушения: &нарушения
          )
        }
      }

      if let расход = объектИлиОтсутствие(шаг["расход_бюджетов"]) {
        for поле in ["токены", "секунды", "изменённые_файлы"] {
          guard let значение = целое(расход[поле]), значение >= 0 else { continue }
          let сложение = суммарныйРасход[поле, default: 0].addingReportingOverflow(значение)
          if сложение.overflow {
            переполнениеРасхода = true
            добавить(
              "переполнение_совокупного_расхода",
              путь: разделительУказателяПаспорта + "состояние/расход_бюджетов/\(поле)",
              сообщение: "Сумма расходов не представима целым числом.",
              нарушения: &нарушения
            )
          } else {
            суммарныйРасход[поле] = сложение.partialValue
          }
        }
      }
    }

    let корректноеСостояниеДиапазона: Bool
    switch состояниеДиапазона {
    case "назначен": корректноеСостояниеДиапазона = переходы.isEmpty
    case "в_работе", "остановлен", "завершён_без_коммита", "отклонён":
      корректноеСостояниеДиапазона = переходы.count < карточки.count
    case "готов": корректноеСостояниеДиапазона = переходы.count == карточки.count
    default: корректноеСостояниеДиапазона = false
    }
    if !корректноеСостояниеДиапазона {
      добавить(
        "состояние_диапазона_не_совпадает_с_префиксом",
        путь: разделительУказателяПаспорта + "состояние/состояние_диапазона",
        сообщение: "Состояние диапазона не соответствует длине завершённого префикса.",
        нарушения: &нарушения
      )
    }

    if состояниеДиапазона == "готов" {
      let обязательные = Set(массивСтрок(объект(назначение["исполнение"])["обязательные_проверки"]))
      if !обязательные.isSubset(of: успешныеПроверки) {
        добавить(
          "обязательная_проверка_отсутствует",
          путь: разделительУказателяПаспорта + "состояние/шаги",
          сообщение: "Готовый диапазон не содержит все обязательные успешные проверки.",
          нарушения: &нарушения
        )
      }
    }

    let заявленныйРасход = объект(состояние["расход_бюджетов"])
    for (поле, сумма) in суммарныйРасход where !переполнениеРасхода {
      if целое(заявленныйРасход[поле]) != сумма {
        добавить(
          "совокупный_расход_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/расход_бюджетов/\(поле)",
          сообщение: "Совокупный расход должен равняться сумме расходов шагов.",
          нарушения: &нарушения
        )
      }
    }

    let очередь = объект(состояние["очередь"])
    let снимок = контекст.снимокОчереди
    if строка(очередь["идентификатор_эпохи_очереди"])
      != снимок.идентификаторЭпохиОчереди
      || строка(очередь["рабочая_ссылка"]) != рабочаяСсылка
      || строка(очередь["идентификатор_физической_рабочей_копии"])
        != идентификаторРабочейКопии
      || очередь["строгий_порядок"] as? Bool != true
      || целое(очередь["последний_порядок_допуска"])
        != снимок.последнийПорядокДопуска
      || строка(очередь["хэш_снимка"]) != снимок.хэшСнимка
      || снимок.рабочаяСсылка != рабочаяСсылка
      || снимок.идентификаторФизическойРабочейКопии != идентификаторРабочейКопии
      || снимок.последнийПорядокДопуска != итоговыйПорядокДопуска
    {
      добавить(
        "снимок_очереди_не_совпадает",
        путь: разделительУказателяПаспорта + "состояние/очередь",
        сообщение:
          "Снимок очереди должен совпадать с рабочей копией, ссылкой и переходами цепочки.",
        нарушения: &нарушения
      )
    }

    проверитьПринятие(
      назначение,
      состояние: состояние,
      карточки: карточки,
      переходы: переходы,
      нарушения: &нарушения
    )
  }

  private static func проверитьСвидетельствоСвязанногоКоммита(
    _ свидетельство: СвидетельствоСвязанногоКоммитаКонечнойЦепочки,
    переход: [String: Any],
    продолжение: [String: Any],
    рабочаяКопия: String?,
    рабочаяСсылка: String?,
    путь: String,
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let допуск = объект(переход["допуск_владельца"])
    let допускСвидетельства = свидетельство.допускВладельца
    let продолжениеСвидетельства = свидетельство.продолжение
    if свидетельство.порядокПерехода != целое(переход["порядок"])
      || свидетельство.идентификаторКарточки
        != строка(переход["идентификатор_карточки"])
      || допускСвидетельства.порядокДопуска != целое(допуск["порядок_допуска"])
      || допускСвидетельства.идентификаторЭпохиОчереди
        != строка(допуск["идентификатор_эпохи_очереди"])
      || допускСвидетельства.идентификаторЗадачи
        != строка(переход["задача_владельца"])
      || допускСвидетельства.идентификаторБилета
        != строка(допуск["идентификатор_билета"])
      || допускСвидетельства.порядковыйНомерБилета
        != целое(допуск["порядковый_номер_билета"])
      || допускСвидетельства.поколениеОчереди
        != строка(допуск["поколение_очереди"])
      || допускСвидетельства.базоваяВершина
        != строка(допуск["базовая_вершина"])
      || допускСвидетельства.хэшСвидетельства
        != строка(допуск["хэш_свидетельства"])
    {
      добавить(
        "свидетельство_допуска_не_совпадает",
        путь: путь + разделительУказателяПаспорта + "допуск_владельца",
        сообщение: "Заявленный допуск не совпадает с авторитетным свидетельством.",
        нарушения: &нарушения
      )
    }
    if продолжениеСвидетельства.идентификаторЗадачи
      != строка(продолжение["идентификатор_задачи"])
      || продолжениеСвидетельства.идентификаторБилета
        != строка(продолжение["идентификатор_билета"])
      || продолжениеСвидетельства.порядковыйНомерБилета
        != целое(продолжение["порядковый_номер_билета"])
      || продолжениеСвидетельства.подтверждённаяВершина
        != строка(продолжение["подтверждённая_вершина"])
    {
      добавить(
        "продолжение_не_совпадает_со_свидетельством",
        путь: путь + разделительУказателяПаспорта + "продолжение",
        сообщение: "Продолжение не совпадает с авторитетным ожидающим билетом.",
        нарушения: &нарушения
      )
    }
    if свидетельство.числоСовпаденийОжидающегоПродолжения != 1 {
      добавить(
        "продолжение_не_ожидало_ровно_один_раз",
        путь: путь + разделительУказателяПаспорта + "продолжение",
        сообщение: "Авторитетный снимок должен содержать продолжение ровно один раз.",
        нарушения: &нарушения
      )
    }
    if свидетельство.идентификаторФизическойРабочейКопии != рабочаяКопия
      || свидетельство.рабочаяСсылка != рабочаяСсылка
      || свидетельство.стараяВершина != строка(переход["входная_вершина"])
      || свидетельство.новаяВершина != строка(переход["коммит"])
      || свидетельство.хэшКвитанции != строка(переход["хэш_квитанции"])
      || свидетельство.хэшСвидетельства
        != строка(переход["хэш_свидетельства_связанного_коммита"])
    {
      добавить(
        "квитанция_связанного_коммита_не_совпадает",
        путь: путь,
        сообщение: "Квитанция не связывает точные вершины, рабочую линию и продолжение.",
        нарушения: &нарушения
      )
    }
  }

  private static func зарегистрироватьИдентичностьБилета(
    _ идентичность: ИдентичностьБилетаКонечнойЦепочки,
    путь: String,
    поЗадаче: inout [String: ИдентичностьБилетаКонечнойЦепочки],
    поБилету: inout [String: ИдентичностьБилетаКонечнойЦепочки],
    поНомеру: inout [Int: ИдентичностьБилетаКонечнойЦепочки],
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let существующие = [
      поЗадаче[идентичность.задача],
      поБилету[идентичность.билет],
      поНомеру[идентичность.номер],
    ].compactMap { $0 }
    if существующие.contains(where: { $0 != идентичность }) {
      добавить(
        "перепривязка_идентичности_билета",
        путь: путь,
        сообщение: "Task, ticket и seq образуют одну неизменяемую FIFO-идентичность.",
        нарушения: &нарушения
      )
      return
    }
    поЗадаче[идентичность.задача] = идентичность
    поБилету[идентичность.билет] = идентичность
    поНомеру[идентичность.номер] = идентичность
  }

  private static func проверитьДопускБезОбходаОжидающихПродолжений(
    _ владелец: ИдентичностьБилетаКонечнойЦепочки,
    ожидающие: inout [Int: ИдентичностьБилетаКонечнойЦепочки],
    путь: String,
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    guard let первыйНомер = ожидающие.keys.min(),
      let первоеПродолжение = ожидающие[первыйНомер]
    else {
      return
    }
    if владелец.номер < первыйНомер {
      return
    }
    if владелец == первоеПродолжение {
      ожидающие.removeValue(forKey: первыйНомер)
      return
    }
    добавить(
      "обход_ожидающего_продолжения",
      путь: путь,
      сообщение: "Следующий допуск не может обойти самый ранний известный билет продолжения.",
      нарушения: &нарушения
    )
  }

  private static func проверитьПринятие(
    _ назначение: [String: Any],
    состояние: [String: Any],
    карточки: [[String: Any]],
    переходы: [[String: Any]],
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let принятие = объект(состояние["принятие"])
    let решение = строка(принятие["состояние"])
    guard решение != "не_решено" else { return }
    if строка(состояние["состояние_диапазона"]) != "готов" {
      добавить(
        "решение_принятия_до_готовности",
        путь: разделительУказателяПаспорта + "состояние/принятие",
        сообщение: "Решение принятия относится только к готовому диапазону.",
        нарушения: &нарушения
      )
    }
    let политика = объект(назначение["политика_принятия"])
    let режим = строка(политика["режим"])
    let последняя = строка(принятие["последняя_карточка"])
    let вершина = строка(принятие["вершина"])
    switch решение {
    case "вся_цепочка":
      if режим != "вся_цепочка" || последняя != nil {
        добавить(
          "принятие_не_соответствует_политике",
          путь: разделительУказателяПаспорта + "состояние/принятие",
          сообщение: "Полное принятие должно соответствовать политике всей цепочки.",
          нарушения: &нарушения
        )
      }
      if вершина != строка(состояние["текущая_вершина"]) {
        добавить(
          "вершина_принятия_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/принятие/вершина",
          сообщение: "Полное принятие должно указывать готовую вершину диапазона.",
          нарушения: &нарушения
        )
      }
    case "точный_префикс":
      let ожидаемаяПоследняя = строка(политика["последняя_карточка"])
      let позиция = карточки.firstIndex {
        строка($0["идентификатор"]) == последняя
      }
      if режим != "точный_префикс" || последняя != ожидаемаяПоследняя
        || позиция == nil
      {
        добавить(
          "принятие_не_соответствует_политике",
          путь: разделительУказателяПаспорта + "состояние/принятие",
          сообщение: "Частичное принятие требует точный именованный префикс политики.",
          нарушения: &нарушения
        )
      }
      if let позиция,
        вершина != строка(переходы[безопасно: позиция]?["коммит"])
      {
        добавить(
          "вершина_принятия_не_совпадает",
          путь: разделительУказателяПаспорта + "состояние/принятие/вершина",
          сообщение: "Вершина принятия должна завершать названный префикс.",
          нарушения: &нарушения
        )
      }
    case "отклонено":
      if последняя != nil || вершина != строка(состояние["текущая_вершина"]) {
        добавить(
          "принятие_не_соответствует_политике",
          путь: разделительУказателяПаспорта + "состояние/принятие",
          сообщение: "Отклонение относится к целой готовой вершине без неявного префикса.",
          нарушения: &нарушения
        )
      }
    default: break
    }
  }

  private static func проверитьВнешниеЗадачи(
    _ состояние: [String: Any],
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    let задачи = массивОбъектов(состояние["внешние_задачи"])
    if !задачи.isEmpty && строка(состояние["состояние_диапазона"]) != "готов" {
      добавить(
        "внешняя_задача_до_готовности_диапазона",
        путь: разделительУказателяПаспорта + "состояние/внешние_задачи",
        сообщение: "Проверяющий и интегратор подключаются только к готовому диапазону.",
        нарушения: &нарушения
      )
    }
    let виды = задачи.compactMap { строка($0["вид"]) }
    if !задачи.isEmpty && Set(виды) != Set(["проверяющая", "интеграционная"]) {
      добавить(
        "неверные_внешние_задачи",
        путь: разделительУказателяПаспорта + "состояние/внешние_задачи",
        сообщение: "Готовый диапазон различает проверяющую и интеграционную задачи.",
        нарушения: &нарушения
      )
    }
    let решение = строка(объект(состояние["принятие"])["состояние"])
    if решение != nil && решение != "не_решено"
      && (задачи.count != 2 || Set(виды) != Set(["проверяющая", "интеграционная"]))
    {
      добавить(
        "решение_без_независимых_внешних_задач",
        путь: разделительУказателяПаспорта + "состояние/принятие",
        сообщение: "Итоговое решение требует отдельные проверяющую и интеграционную задачи.",
        нарушения: &нарушения
      )
    }
    let владельцы = Set(
      массивОбъектов(состояние["переходы"]).compactMap {
        строка($0["задача_владельца"])
      }
    )
    let продолжения = Set(
      массивОбъектов(состояние["переходы"]).compactMap {
        строка(объект($0["продолжение"])["идентификатор_задачи"])
      }
    )
    let идентификаторы = задачи.compactMap { строка($0["идентификатор"]) }
    let внешниеИдентификаторы = Set(идентификаторы)
    if идентификаторы.count != внешниеИдентификаторы.count {
      добавить(
        "повтор_идентификатора_внешней_задачи",
        путь: разделительУказателяПаспорта + "состояние/внешние_задачи",
        сообщение: "Проверяющая и интеграционная задачи должны быть различными задачами.",
        нарушения: &нарушения
      )
    }
    if !владельцы.isDisjoint(with: внешниеИдентификаторы)
      || !продолжения.isDisjoint(with: внешниеИдентификаторы)
    {
      добавить(
        "внешняя_задача_владеет_рабочей_веткой",
        путь: разделительУказателяПаспорта + "состояние/внешние_задачи",
        сообщение: "Проверяющий и интегратор не могут быть владельцами или продолжениями ветки.",
        нарушения: &нарушения
      )
    }
  }

  private static func разобрать(
    _ данные: Data,
    имя: String,
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) -> [String: Any]? {
    guard !данные.isEmpty, данные.count <= предельныйРазмерПаспортаКонечнойЦепочки else {
      добавить(
        "неверный_json",
        путь: разделительУказателяПаспорта + "\(имя)",
        сообщение: "Вход отсутствует или превышает предел размера.",
        нарушения: &нарушения
      )
      return nil
    }
    var обнаружитель = JSONDuplicateKeyDetector(data: данные)
    do {
      let повторныеПути = try обнаружитель.scan()
      if !повторныеПути.isEmpty {
        for путь in повторныеПути {
          добавить(
            "повторный_ключ",
            путь: разделительУказателяПаспорта + "\(имя)" + путь,
            сообщение: "JSON-объект содержит повторный ключ.",
            нарушения: &нарушения
          )
        }
        return nil
      }
    } catch JSONScanError.structureLimitExceeded {
      добавить(
        "предел_структуры_json",
        путь: разделительУказателяПаспорта + "\(имя)",
        сообщение: "JSON превышает предел глубины или числа узлов.",
        нарушения: &нарушения
      )
      return nil
    } catch {
      добавить(
        "неверный_json",
        путь: разделительУказателяПаспорта + "\(имя)",
        сообщение: "Вход должен быть завершённым JSON-объектом.",
        нарушения: &нарушения
      )
      return nil
    }
    guard let значение = try? JSONSerialization.jsonObject(with: данные),
      let объект = значение as? [String: Any]
    else {
      добавить(
        "неверный_json",
        путь: разделительУказателяПаспорта + "\(имя)",
        сообщение: "Вход должен быть завершённым JSON-объектом.",
        нарушения: &нарушения
      )
      return nil
    }
    if let путь = путьПервойНенормализованнойСтроки(объект) {
      добавить(
        "строка_не_NFC",
        путь: разделительУказателяПаспорта + "\(имя)" + путь,
        сообщение: "Ключи и строковые значения должны быть нормализованы в NFC.",
        нарушения: &нарушения
      )
      return nil
    }
    return объект
  }

  private static func проверитьЗакрытыйОбъект(
    _ объект: [String: Any],
    допустимые: Set<String>,
    обязательные: Set<String>,
    путь: String,
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    for ключ in объект.keys where !допустимые.contains(ключ) {
      добавить(
        "неизвестное_поле",
        путь: путь + разделительУказателяПаспорта + ключ,
        сообщение: "Закрытый объект содержит неизвестное поле.",
        нарушения: &нарушения
      )
    }
    for ключ in обязательные where объект[ключ] == nil {
      добавить(
        "обязательное_поле_отсутствует",
        путь: путь + разделительУказателяПаспорта + ключ,
        сообщение: "Закрытый объект не содержит обязательное поле.",
        нарушения: &нарушения
      )
    }
  }

  private static func отчёт(
    идентификаторЦепочки: String?,
    числоШагов: Int,
    состояниеДиапазона: String?,
    текущаяВершина: String?,
    готоваяВершина: String?,
    хэшНазначения: String?,
    нарушения: [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) -> ОтчётПроверкиДелегированияКонечнойЦепочки {
    let упорядоченные = Array(Set(нарушения)).sorted {
      if $0.код != $1.код { return $0.код < $1.код }
      if $0.путь != $1.путь { return $0.путь < $1.путь }
      return $0.сообщение < $1.сообщение
    }
    return ОтчётПроверкиДелегированияКонечнойЦепочки(
      решение: упорядоченные.isEmpty ? .допустимо : .недопустимо,
      идентификаторЦепочки: идентификаторЦепочки,
      числоШагов: числоШагов,
      состояниеДиапазона: состояниеДиапазона,
      текущаяВершина: текущаяВершина,
      готоваяВершина: упорядоченные.isEmpty ? готоваяВершина : nil,
      хэшНазначения: хэшНазначения,
      нарушения: упорядоченные
    )
  }

  private static func добавить(
    _ код: String,
    путь: String,
    сообщение: String,
    нарушения: inout [НарушениеПроверкиДелегированияКонечнойЦепочки]
  ) {
    нарушения.append(
      НарушениеПроверкиДелегированияКонечнойЦепочки(
        код: код,
        путь: путь,
        сообщение: сообщение
      )
    )
  }

  private static func хэшОбъекта(
    _ исходный: [String: Any],
    исключая поле: String
  ) -> String? {
    var объект = исходный
    объект.removeValue(forKey: поле)
    guard JSONSerialization.isValidJSONObject(объект),
      let данные = try? JSONSerialization.data(
        withJSONObject: объект,
        options: [.sortedKeys, .withoutEscapingSlashes]
      )
    else { return nil }
    return "sha256:"
      + SHA256.hash(data: данные).map {
        String(format: "%02x", $0)
      }.joined()
  }

  private static func объект(_ значение: Any?) -> [String: Any] {
    значение as? [String: Any] ?? [:]
  }


        сообщение: "Состояние относится к другой физической рабочей копии.",
        нарушения: &нарушения
      )
    }
    if строка(состояние["рабочая_ссылка"]) != рабочаяСсылка {
      добавить(
        "несовпавшая_рабочая_ссылка",
        путь: разделительУказателяПаспорта + "состояние/рабочая_ссылка",
        сообщение: "Состояние относится к другой рабочей ссылке.",
        нарушения: &нарушения
      )
    }
    if строка(состояние["исходный_коммит"]) != строка(назначение["исходный_коммит"]) {
      добавить(
        "исходный_коммит_состояния_не_совпадает",

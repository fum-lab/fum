          "Замороженный дочерний диапазон нелинеен."
        )
      }
      return КоммитПринятогоДиапазонаЦепочки(
        объект: объект,
        родители: Array(части.dropFirst())
      )
    }
    return ЗамороженныйРезультатРебёнкаДляМодерацииЦепочки(
      идентификаторФорка: цепочка.идентификаторФорка,

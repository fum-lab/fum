      полныйДиапазон: конверт.полныйДиапазон,
      роль: конверт.роль,
      хэшМанифестаФикстуры: конверт.хэшМанифестаФикстуры
    )
    return конверт.хэшКонверта == (try хэшАвтономнойПриёмки(нагрузка))
  }

  fileprivate func провестиОфициальноеРевью(
    цепочка: СвидетельствоДочернейРолевойЦепочки,
    другойРебёнок: СвидетельствоДочернейРолевойЦепочки?,
    конверт: КонвертАвтономногоПредложенияИзФорка,
    исходныйРепозиторий: URL,
    репозиторийДругогоРебёнка: URL?,
    ядро: URL,
    исход: ИсходКорневогоРевьюЦепочки,
    проверяющий: String,
    актуальнаяВершина: String,
    актуальнаяБаза: String? = nil,
    базоваяСборка: String,
    ожидаемаяРолеваяВершина: String,
    паспортМодерации: ПаспортМодерацииКорневойЦепочки? = nil,
    сохранятьСвидетельство: Bool = true,
    подменитьАктуальныйХэшКритериев: Bool = false,
    подменитьДиапазонКонверта: Bool = false
  ) throws -> РезультатОфициальногоРевью {
    let поколение = "поколение.параллельные-универсальные-подузлы.1"
    let идентификаторЯдра = "репозиторий.ядро"
    let ссылкаЯдра = "refs/heads/основная"
    let путьИсточника = исходныйРепозиторий.standardizedFileURL
      .resolvingSymlinksInPath().path.precomposedStringWithCanonicalMapping
    let путьЯдра = ядро.standardizedFileURL.resolvingSymlinksInPath().path
      .precomposedStringWithCanonicalMapping
    let коммиты = try цепочка.коммиты.map { объект -> КоммитПринятогоДиапазонаЦепочки in
      let части = try текстКомандыКонтроляВерсий(
        ["rev-list", "--parents", "-n", "1", объект],
        в: исходныйРепозиторий
      ).split(separator: " ").map(String.init)
      guard части.first == объект, части.count == 2 else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Ревью обнаружило нелинейный реальный commit: \(объект)."
        )
      }
      return КоммитПринятогоДиапазонаЦепочки(
        объект: объект,
        родители: Array(части.dropFirst())
      )
    }
    let хэшиПаспортов = try коммиты.map { try хэшАвтономнойПриёмки($0) }
    let хэшКритериев = try хэшАвтономнойПриёмки(
      ["синтетический-навык", "точный-диапазон", "автономная-граница"]
    )
    let хэшПроверки = try хэшАвтономнойПриёмки(
      [цепочка.база, цепочка.вершина, "артефакт-прочитан"]
    )
    let официальныйКонверт = КонвертЗапросаСлиянияЦепочки(
      поставщик: цепочка.идентификаторФорка,
      исходныйРепозиторий: цепочка.идентификаторРепозитория,
      целевойРепозиторий: идентификаторЯдра,
      исходнаяСсылка: цепочка.рабочаяСсылка,
      целеваяСсылка: ссылкаЯдра,
      идентификатор: конверт.идентификатор + ".ядро",
      поколениеНазначения: поколение,
      база: цепочка.база,
      вершина: цепочка.вершина,
      диапазон: подменитьДиапазонКонверта
        ? Array(цепочка.коммиты.dropLast()) : цепочка.коммиты,

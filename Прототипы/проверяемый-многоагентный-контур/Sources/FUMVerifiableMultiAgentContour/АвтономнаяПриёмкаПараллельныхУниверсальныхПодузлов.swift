      новыйКонвертПрефикса: nil,
      новоеПоколениеДоработки: исход == .наДоработку
        ? "поколение.синтетический-навык.доработка.2" : nil,
      актуальноеПоколениеНазначения: поколение,
      актуальнаяБаза: актуальнаяБаза ?? цепочка.база,

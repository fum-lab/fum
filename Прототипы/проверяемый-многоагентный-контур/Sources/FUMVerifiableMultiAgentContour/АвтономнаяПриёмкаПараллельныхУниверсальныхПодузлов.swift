  fileprivate func запланироватьСобытиеСаги(
    _ событие: ОграждённоеСобытиеКорневойИнтеграцииЦепочки,
    в журнал: inout ЖурналАвтономнойСаги
  ) throws {
    _ = try восстановитьСостояниеСаги(из: журнал)
    if журнал.ожидающееСобытие == событие {
      return
    }
    if журнал.ожидающееСобытие == nil,
      журнал.применённыеСобытия.last == событие
    {
      return
    }
    guard журнал.ожидающееСобытие == nil,
      !журнал.применённыеСобытия.contains(событие)
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сага уже содержит несовместимое либо неупорядоченное событие."
      )
    }
    var запланированныйЖурнал = журнал
    запланированныйЖурнал.ожидающееСобытие = событие
    _ = try восстановитьСостояниеСаги(из: запланированныйЖурнал)
    try записатьЖурналСаги(запланированныйЖурнал)
    let прочитанныйЖурнал = try прочитатьЖурналСаги()
    guard прочитанныйЖурнал == запланированныйЖурнал else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сага не перечитала exact запланированное событие."
      )
    }
    журнал = прочитанныйЖурнал
  }

  fileprivate func подтвердитьСобытиеСаги(
    _ событие: ОграждённоеСобытиеКорневойИнтеграцииЦепочки,
    в журнал: inout ЖурналАвтономнойСаги
  ) throws {
    _ = try восстановитьСостояниеСаги(из: журнал)
    if журнал.ожидающееСобытие == nil,
      журнал.применённыеСобытия.last == событие
    {
      return
    }
    guard журнал.ожидающееСобытие == событие,
      !журнал.применённыеСобытия.contains(событие)
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сага не восстановила exact ожидающее событие."
      )
    }
    var подтверждённыйЖурнал = журнал
    подтверждённыйЖурнал.применённыеСобытия.append(событие)
    подтверждённыйЖурнал.ожидающееСобытие = nil
    _ = try восстановитьСостояниеСаги(из: подтверждённыйЖурнал)
    try записатьЖурналСаги(подтверждённыйЖурнал)
    let прочитанныйЖурнал = try прочитатьЖурналСаги()
    guard прочитанныйЖурнал == подтверждённыйЖурнал else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сага не перечитала exact подтверждённое событие."
      )
    }
    журнал = прочитанныйЖурнал
  }

  fileprivate func восстановитьСостояниеСаги(
    из журнал: ЖурналАвтономнойСаги
  ) throws -> СостояниеКорневойИнтеграцииЦепочки {
    let отчёт = ПроверкаКорневогоРевьюИИнтеграцииЦепочки.проверить(журнал.снимок)
    guard отчёт.решение == .допустимо,
      отчёт.кодыНарушений.isEmpty,
      let разрешение = отчёт.разрешение
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сага не восстановила валидатором исходное разрешение."
      )
    }
    let ожидаемыеСостояния: [СостояниеПереходаКорневойИнтеграцииЦепочки] = [
      .подготовлено,
      .принятоВЯдреСинхронизацияРебёнкаОжидается,
      .согласованиеСсылокСборкиОжидается,
      .завершено,
    ]
    var состояние = СостояниеКорневойИнтеграцииЦепочки(разрешение: разрешение)
    guard состояние.маршрут == .общийВкладВЯдро,
      состояние.состояниеПерехода == ожидаемыеСостояния[0],
      состояние.кодОтказа == nil,
      журнал.применённыеСобытия.count < ожидаемыеСостояния.count
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сага не восстановила начальное состояние общего вклада в ядро."
      )
    }
    for (номер, событие) in журнал.применённыеСобытия.enumerated() {
      let следующее = РедукторКорневойИнтеграцииЦепочки.применить(
        событие,
        к: состояние
      )
      guard следующее != состояние,
        следующее.кодОтказа == nil,
        следующее.состояниеПерехода == ожидаемыеСостояния[номер + 1]
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Применённое событие саги нарушило exact последовательность редуктора."
        )
      }
      состояние = следующее
    }
    if let ожидающее = журнал.ожидающееСобытие {
      let следующийНомер = журнал.применённыеСобытия.count + 1
      guard следующийНомер < ожидаемыеСостояния.count,
        !журнал.применённыеСобытия.contains(ожидающее)
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Pending-событие саги дублирует применённое либо выходит за терминал."
        )
      }
      let гипотетическое = РедукторКорневойИнтеграцииЦепочки.применить(
        ожидающее,
        к: состояние
      )
      guard гипотетическое != состояние,
        гипотетическое.кодОтказа == nil,
        гипотетическое.состояниеПерехода == ожидаемыеСостояния[следующийНомер]
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Pending-событие не образует следующий exact переход редуктора."
        )
      }
    }
    return состояние
  }
}

extension СтендАвтономнойПриёмкиПараллельныхПодузлов {
  fileprivate func подготовитьСинхронизациюРебёнка(
    форк: URL,
    вершинаЯдра: String,
    очередь: ПаспортОчередиКомпонентаАвтономнойПриёмки
  ) throws -> ПодготовленнаяСинхронизацияРебёнка {
    let рабочаяКопия = корень.appending(
      path: "синхронизированная-рабочая-копия-ребёнка"
    )
    _ = try выполнитьКомандуКонтроляВерсий(
      ["clone", "--no-checkout", форк.path, рабочаяКопия.path], в: корень)
    _ = try выполнитьКомандуКонтроляВерсий(["checkout", "--detach", вершинаЯдра], в: рабочаяКопия)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["switch", "--create", "синхронизированная/основная"],
      в: рабочаяКопия
    )
    try записать(
      try каноническиеДанныеАвтономнойПриёмки(очередь),
      по: рабочаяКопия.appending(path: "Планирование/очередь-форка.json")
    )
    try записать(
      Data(
        "# Синхронизация fork\n\nДочерняя вершина создана строго поверх принятой вершины ядра.\n"
          .utf8
      ),
      по: рабочаяКопия.appending(path: "Синхронизация/подтверждение.md")
    )
    _ = try выполнитьКомандуКонтроляВерсий(
      [
        "add", "--", "Планирование/очередь-форка.json",
        "Синхронизация/подтверждение.md",
      ],
      в: рабочаяКопия
    )
    let дерево = try текстКомандыКонтроляВерсий(["write-tree"], в: рабочаяКопия)
    let дата = "2001-01-01T00:00:04Z"
    let автор = try выполнитьКомандуКонтроляВерсий(
      ["var", "GIT_AUTHOR_IDENT"],
      в: рабочаяКопия,
      дата: дата
    )
    let фиксатор = try выполнитьКомандуКонтроляВерсий(
      ["var", "GIT_COMMITTER_IDENT"],
      в: рабочаяКопия,
      дата: дата
    )
    let сообщение = "Синхронизировать существующий fork с ядром"
    let данныеКоммита = Data(
      [
        "tree \(дерево)",
        "parent \(вершинаЯдра)",
        "author \(автор)",
        "committer \(фиксатор)",
        "",
        сообщение,
        "",
      ].joined(separator: "\n").utf8
    )
    let вершина = try выполнитьКомандуКонтроляВерсий(
      ["hash-object", "-t", "commit", "--stdin"],
      в: рабочаяКопия,
      ввод: данныеКоммита
    )
    guard
      !(try командаКонтроляВерсийУспешна(
        ["cat-file", "-e", "\(вершина)^{commit}"],
        в: рабочаяКопия
      ))
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Дочерний commit физически появился до принятого ревью."
      )
    }
    return ПодготовленнаяСинхронизацияРебёнка(
      рабочаяКопия: рабочаяКопия,
      вершина: вершина,
      родитель: вершинаЯдра,
      дерево: дерево,
      очередь: очередь
    )
  }

  fileprivate func завершитьСинхронизациюРебёнка(
    подготовка: ПодготовленнаяСинхронизацияРебёнка,
    ядро: URL,
    форк: URL,
    принятаяВершинаЯдра: String,
    хэшРешения: String
  ) throws -> String {
    guard подготовка.родитель == принятаяВершинаЯдра else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Подготовленная ролевая вершина не связана с принятой вершиной ядра."
      )
    }
    guard
      !(try командаКонтроляВерсийУспешна(
        ["cat-file", "-e", "\(подготовка.вершина)^{commit}"],
        в: подготовка.рабочаяКопия
      ))
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Ролевая вершина существовала до post-acceptance-перехода."
      )
    }
    _ = try выполнитьКомандуКонтроляВерсий(
      ["commit", "--quiet", "-m", "Синхронизировать существующий fork с ядром"],
      в: подготовка.рабочаяКопия,
      дата: "2001-01-01T00:00:04Z"
    )
    let созданнаяВершина = try текстКомандыКонтроляВерсий(
      ["rev-parse", "HEAD"],
      в: подготовка.рабочаяКопия
    )
    let созданноеДерево = try текстКомандыКонтроляВерсий(
      ["rev-parse", "HEAD^{tree}"],
      в: подготовка.рабочаяКопия
    )
    let родители = try текстКомандыКонтроляВерсий(
      ["rev-list", "--parents", "-n", "1", созданнаяВершина],
      в: подготовка.рабочаяКопия
    ).split(separator: " ").map(String.init)
    guard созданнаяВершина == подготовка.вершина,
      созданноеДерево == подготовка.дерево,
      родители == [созданнаяВершина, принятаяВершинаЯдра]
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Post-acceptance commit не совпал с предварительно проверенным объектом."
      )
    }
    let целеваяСсылкаЗеркала = "refs/heads/зеркало/master"
    let целеваяРолеваяСсылка = "refs/heads/синхронизированная/основная"
    let шестнадцатеричныеЦифры = CharacterSet(charactersIn: "0123456789abcdef")
    let суффиксРешения = String(хэшРешения.dropFirst("sha256:".count))
    guard хэшРешения.hasPrefix("sha256:"), хэшРешения.count == 71,
      суффиксРешения.unicodeScalars.allSatisfy(шестнадцатеричныеЦифры.contains)
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Синхронизация fork не получила полный хэш официального решения."
      )
    }
    let удержаниеЯдра = "refs/fum/удержание/синхронизация/\(суффиксРешения)/ядро"
    let удержаниеРебёнка =
      "refs/fum/удержание/синхронизация/\(суффиксРешения)/ребёнок"
    let намерениеСбояСинхронизации =
      "атомарно_обновить_зеркальную_и_ролевую_ссылки"
    let наблюдениеСбояСинхронизации =
      "две_ссылки_обновлены:\(принятаяВершинаЯдра):\(подготовка.вершина)"
    try сбои.запланировать(
      .синхронизацияФорка,
      намерение: намерениеСбояСинхронизации
    )
    _ = try выполнитьКомандуКонтроляВерсий(
      [
        "fetch", "--quiet", "--no-tags", "--no-write-fetch-head", "--",
        ядро.path, "refs/heads/основная",
      ],
      в: форк
    )
    _ = try выполнитьКомандуКонтроляВерсий(
      [
        "fetch", "--quiet", "--no-tags", "--no-write-fetch-head", "--",
        подготовка.рабочаяКопия.path, "refs/heads/синхронизированная/основная",
      ],
      в: форк
    )
    let фактическиеРодители = try текстКомандыКонтроляВерсий(
      ["rev-list", "--parents", "-n", "1", подготовка.вершина],
      в: форк
    ).split(separator: " ").map(String.init)
    guard
      try командаКонтроляВерсийУспешна(
        ["cat-file", "-e", "\(принятаяВершинаЯдра)^{commit}"],
        в: форк
      ),
      try командаКонтроляВерсийУспешна(
        ["cat-file", "-e", "\(подготовка.вершина)^{commit}"],
        в: форк
      ),
      фактическиеРодители == [подготовка.вершина, принятаяВершинаЯдра]
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Переданные объекты не образуют exact post-acceptance-топологию."
      )
    }
    let строкиПодготовкиУдержания = [
      "start",
      "verify \(целеваяСсылкаЗеркала)",
      "verify \(целеваяРолеваяСсылка)",
      "create \(удержаниеЯдра) \(принятаяВершинаЯдра)",
      "create \(удержаниеРебёнка) \(подготовка.вершина)",
      "prepare",
      "commit",
      "",
    ]
    _ = try выполнитьКомандуКонтроляВерсий(
      ["update-ref", "--no-deref", "--stdin"],
      в: форк,
      ввод: Data(строкиПодготовкиУдержания.joined(separator: "\n").utf8)
    )
    let строкиТранзакции = [
      "start",
      "create \(целеваяСсылкаЗеркала) \(принятаяВершинаЯдра)",
      "create \(целеваяРолеваяСсылка) \(подготовка.вершина)",
      "delete \(удержаниеЯдра) \(принятаяВершинаЯдра)",
      "delete \(удержаниеРебёнка) \(подготовка.вершина)",
      "prepare",
      "commit",
      "",
    ]
    let транзакция = Data(строкиТранзакции.joined(separator: "\n").utf8)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["update-ref", "--no-deref", "--stdin"],
      в: форк,
      ввод: транзакция
    )
    do {
      try сбои.записатьЭффектИПотерятьОтвет(
        .синхронизацияФорка,
        намерение: намерениеСбояСинхронизации,
        наблюдение: наблюдениеСбояСинхронизации
      )
    } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.намеренноеПрерывание {
      let новыйСеанс = try новыйСеансВосстановления()
      let строкиПроверкиУспеха = [
        "start",
        "verify \(целеваяСсылкаЗеркала) \(принятаяВершинаЯдра)",
        "verify \(целеваяРолеваяСсылка) \(подготовка.вершина)",
        "verify \(удержаниеЯдра)",
        "verify \(удержаниеРебёнка)",
        "prepare",
        "commit",
        "",
      ]
      var точныйКортежУспеха =
        try новыйСеанс
        .командаКонтроляВерсийУспешна(
          ["update-ref", "--no-deref", "--stdin"],
          в: форк,
          ввод: Data(строкиПроверкиУспеха.joined(separator: "\n").utf8)
        )
      if !точныйКортежУспеха {
        let строкиПроверкиОжидания = [
          "start",
          "verify \(целеваяСсылкаЗеркала)",
          "verify \(целеваяРолеваяСсылка)",
          "verify \(удержаниеЯдра) \(принятаяВершинаЯдра)",
          "verify \(удержаниеРебёнка) \(подготовка.вершина)",
          "prepare",
          "commit",
          "",
        ]
        let точныйКортежОжидания =
          try новыйСеанс
          .командаКонтроляВерсийУспешна(
            ["update-ref", "--no-deref", "--stdin"],
            в: форк,
            ввод: Data(строкиПроверкиОжидания.joined(separator: "\n").utf8)
          )
        guard точныйКортежОжидания else {
          throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
            "Новый сеанс обнаружил mixed либо third-state двух ссылок fork."
          )
        }
        _ = try новыйСеанс.выполнитьКомандуКонтроляВерсий(
          ["update-ref", "--no-deref", "--stdin"],
          в: форк,
          ввод: транзакция
        )
        точныйКортежУспеха = try новыйСеанс.командаКонтроляВерсийУспешна(
          ["update-ref", "--no-deref", "--stdin"],
          в: форк,
          ввод: Data(строкиПроверкиУспеха.joined(separator: "\n").utf8)
        )
      }
      guard точныйКортежУспеха else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Повтор транзакции fork не завершил exact кортеж ссылок."
        )
      }
      try новыйСеанс.сбои.восстановитьПослеПотериОтвета(
        .синхронизацияФорка,
        намерение: намерениеСбояСинхронизации,
        наблюдение: наблюдениеСбояСинхронизации
      ) {
        точныйКортежУспеха
      }
    }
    return подготовка.вершина
  }

  fileprivate func обновитьСборкуОднойСравнительнойЗаменой(
    сборка: URL,
    базоваяСборка: String,
    новоеЯдро: String,
    новыйРебёнок: String
  ) throws -> РезультатОбновленияАвтономнойСборки {
    let локальнаяРабочаяКопия = корень.appending(path: "рабочая-копия-сборки")
    _ = try выполнитьКомандуКонтроляВерсий(
      ["clone", сборка.path, локальнаяРабочаяКопия.path], в: корень)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["update-index", "--cacheinfo", "160000,\(новоеЯдро),Компоненты/ядро"],
      в: локальнаяРабочаяКопия
    )
    _ = try выполнитьКомандуКонтроляВерсий(
      [
        "update-index", "--cacheinfo",
        "160000,\(новыйРебёнок),Компоненты/дочернее-ответвление",
      ],
      в: локальнаяРабочаяКопия
    )
    _ = try выполнитьКомандуКонтроляВерсий(
      ["commit", "--quiet", "-m", "Согласовать gitlink ядра и дочернего fork"],
      в: локальнаяРабочаяКопия,
      дата: "2001-01-01T00:00:05Z"
    )
    let вершина = try текстКомандыКонтроляВерсий(["rev-parse", "HEAD"], в: локальнаяРабочаяКопия)
    let родители = try текстКомандыКонтроляВерсий(
      ["rev-list", "--parents", "-n", "1", вершина],
      в: локальнаяРабочаяКопия
    ).split(separator: " ").map(String.init)
    let ссылкаПодмодуляЯдра = try прочитатьСсылкуПодмодуля(
      путь: "Компоненты/ядро",
      в: вершина,
      репозиторий: локальнаяРабочаяКопия
    )
    let ссылкаПодмодуляРебёнка = try прочитатьСсылкуПодмодуля(
      путь: "Компоненты/дочернее-ответвление",
      в: вершина,
      репозиторий: локальнаяРабочаяКопия
    )
    guard родители == [вершина, базоваяСборка],
      ссылкаПодмодуляЯдра == новоеЯдро,
      ссылкаПодмодуляРебёнка == новыйРебёнок,
      try текстКомандыКонтроляВерсий(["rev-parse", "refs/heads/основная"], в: сборка)
        == базоваяСборка
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сборочный кандидат не имеет exact родителя, двух gitlink или исходной цели."
      )
    }
    let ссылкаКандидата = "refs/fum/удержание/сборка/\(вершина)"
    let намерениеСбояСборки =
      "одной_сравнительной_заменой_согласовать_две_ссылки_подмодулей"
    let наблюдениеСбояСборки = "сборочная_ссылка_продвинута:\(вершина)"
    try сбои.запланировать(
      .сборочнаяСсылкаПодмодуля,
      намерение: намерениеСбояСборки
    )
    _ = try выполнитьКомандуКонтроляВерсий(
      ["push", сборка.path, "HEAD:\(ссылкаКандидата)"],
      в: локальнаяРабочаяКопия
    )
    guard try вершинаСсылкиИлиОтсутствие(ссылкаКандидата, в: сборка) == вершина else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сборочный holding ref не закрепил exact кандидат."
      )
    }
    var числоСравненийИЗамен = 0
    let строкиТранзакции = [
      "start",
      "update refs/heads/основная \(вершина) \(базоваяСборка)",
      "delete \(ссылкаКандидата) \(вершина)",
      "prepare",
      "commit",
      "",
    ]
    let транзакция = Data(строкиТранзакции.joined(separator: "\n").utf8)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["update-ref", "--no-deref", "--stdin"],
      в: сборка,
      ввод: транзакция
    )
    числоСравненийИЗамен += 1
    do {
      try сбои.записатьЭффектИПотерятьОтвет(
        .сборочнаяСсылкаПодмодуля,
        намерение: намерениеСбояСборки,
        наблюдение: наблюдениеСбояСборки
      )
    } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.намеренноеПрерывание {
      let новыйСеанс = try новыйСеансВосстановления()
      let восстановленныйЖурнал = try новыйСеанс.прочитатьЖурналСаги()
      let восстановленноеСостояние = try новыйСеанс.восстановитьСостояниеСаги(
        из: восстановленныйЖурнал
      )
      let строкиПроверкиУспеха = [
        "start",
        "verify refs/heads/основная \(вершина)",
        "verify \(ссылкаКандидата)",
        "prepare",
        "commit",
        "",
      ]
      var точныйКортежУспеха = try новыйСеанс.командаКонтроляВерсийУспешна(
        ["update-ref", "--no-deref", "--stdin"],
        в: сборка,
        ввод: Data(строкиПроверкиУспеха.joined(separator: "\n").utf8)
      )
      if !точныйКортежУспеха {
        let строкиПроверкиОжидания = [
          "start",
          "verify refs/heads/основная \(базоваяСборка)",
          "verify \(ссылкаКандидата) \(вершина)",
          "prepare",
          "commit",
          "",
        ]
        guard
          try новыйСеанс.командаКонтроляВерсийУспешна(
            ["update-ref", "--no-deref", "--stdin"],
            в: сборка,
            ввод: Data(строкиПроверкиОжидания.joined(separator: "\n").utf8)
          )
        else {
          throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
            "Новый сеанс обнаружил mixed либо third-state сборочного CAS."
          )
        }
        _ = try новыйСеанс.выполнитьКомандуКонтроляВерсий(
          ["update-ref", "--no-deref", "--stdin"],
          в: сборка,
          ввод: транзакция
        )
        точныйКортежУспеха = try новыйСеанс.командаКонтроляВерсийУспешна(
          ["update-ref", "--no-deref", "--stdin"],
          в: сборка,
          ввод: Data(строкиПроверкиУспеха.joined(separator: "\n").utf8)
        )
      }
      guard
        восстановленноеСостояние.состояниеПерехода
          == .согласованиеСсылокСборкиОжидается,
        восстановленныйЖурнал.ожидающееСобытие != nil,
        точныйКортежУспеха
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Новый сеанс не восстановил победивший сборочный CAS."
        )
      }
      try новыйСеанс.сбои.восстановитьПослеПотериОтвета(
        .сборочнаяСсылкаПодмодуля,
        намерение: намерениеСбояСборки,
        наблюдение: наблюдениеСбояСборки
      ) {
        try новыйСеанс.прочитатьСсылкуПодмодуля(
          путь: "Компоненты/ядро",
          в: вершина,
          репозиторий: сборка
        ) == новоеЯдро
          && новыйСеанс.прочитатьСсылкуПодмодуля(
            путь: "Компоненты/дочернее-ответвление",
            в: вершина,
            репозиторий: сборка
          ) == новыйРебёнок
      }
    }
    return РезультатОбновленияАвтономнойСборки(
      вершина: вершина,
      ссылкаПодмодуляЯдра: ссылкаПодмодуляЯдра,
      ссылкаПодмодуляРебёнка: ссылкаПодмодуляРебёнка,
      числоСравненийИЗамен: числоСравненийИЗамен
    )
  }

  fileprivate func прочитатьСсылкуПодмодуля(путь: String, в вершина: String, репозиторий: URL)
    throws -> String
  {
    let строка = try текстКомандыКонтроляВерсий(["ls-tree", вершина, "--", путь], в: репозиторий)
    let поля = строка.split(whereSeparator: { $0 == " " || $0 == "\t" })
    guard поля.count >= 3, поля[0] == "160000", поля[1] == "commit" else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сборка не содержит ожидаемый gitlink: \(путь)."
      )
    }
    return String(поля[2])
  }

  fileprivate func проверитьГраницыСбоев(
    точныйПовторИнтеграции: Bool,
    рабочиеКопии: [String: URL],
    репозитории: [ОжидаемыйИнвентарьРепозитория],
    ожидаемыеФайлыСостояния: [String]
  ) throws -> ДоказательствоГраницСбоев {
    let точки = сбои.точки
    guard try сбои.всеФайлыУчтены() else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Каталоги точек сбоя содержат неучтённые файлы."
      )
    }
    let кореньСостояния = корень.appending(path: "состояние")
    guard
      let перечислитель = файловаяСистема.enumerator(
        at: кореньСостояния,
        includingPropertiesForKeys: [.isRegularFileKey],
        options: []
      )
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Не удалось построить рекурсивный инвентарь состояния."
      )
    }
    var фактическиеФайлыСостояния: [String] = []
    for case let адрес as URL in перечислитель {
      let свойства = try адрес.resourceValues(forKeys: [.isRegularFileKey])
      guard свойства.isRegularFile == true else { continue }
      let корневыеКомпоненты = кореньСостояния.standardizedFileURL.pathComponents
      let компоненты = адрес.standardizedFileURL.pathComponents
      guard компоненты.count > корневыеКомпоненты.count,
        Array(компоненты.prefix(корневыеКомпоненты.count)) == корневыеКомпоненты
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Инвентарь состояния вышел за свой корень."
        )
      }
      фактическиеФайлыСостояния.append(
        компоненты.dropFirst(корневыеКомпоненты.count).joined(separator: "/")
      )
    }
    фактическиеФайлыСостояния.sort()
    guard фактическиеФайлыСостояния == ожидаемыеФайлыСостояния.sorted() else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Рекурсивный инвентарь состояния содержит пропуск или неожиданный файл."
      )
    }

    var ссылкиРепозиториев: [String: [String]] = [:]
    var проверенныеРепозитории: [String] = []
    for репозиторий in репозитории.sorted(by: { $0.имя < $1.имя }) {
      let строки = try текстКомандыКонтроляВерсий(
        ["for-each-ref", "--sort=refname", "--format=%(refname) %(objectname)"],
        в: репозиторий.адрес
      ).split(separator: "\n").map(String.init)
      let ожидаемыеСтроки = репозиторий.ссылки.map {
        "\($0.key) \($0.value)"
      }.sorted()
      guard строки == ожидаемыеСтроки else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Bare-репозиторий содержит неожиданный ref: \(репозиторий.имя)."
        )
      }
      let проверкаОбъектов = try текстКомандыКонтроляВерсий(
        ["fsck", "--strict", "--no-reflogs", "--unreachable", "--no-progress"],
        в: репозиторий.адрес
      )
      guard проверкаОбъектов.isEmpty else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Bare-репозиторий содержит недостижимый объект: \(репозиторий.имя)."
        )
      }
      ссылкиРепозиториев[репозиторий.имя] = строки.map { строка in
        guard строка.hasPrefix("refs/fum/корневая-интеграция/") else {
          return строка
        }
        let части = строка.split(separator: " ", maxSplits: 1).map(String.init)
        return части.count == 2
          ? "refs/fum/корневая-интеграция/<решение> \(части[1])"
          : строка
      }
      проверенныеРепозитории.append(репозиторий.имя)
    }

    var чистыеРабочиеКопии: [String] = []
    for имя in рабочиеКопии.keys.sorted() {
      guard let рабочаяКопия = рабочиеКопии[имя] else { continue }
      let рабочаяКопияЧиста = try текстКомандыКонтроляВерсий(
        ["status", "--porcelain=v1", "--untracked-files=all"],
        в: рабочаяКопия
      ).isEmpty
      let проверкаОбъектов = try текстКомандыКонтроляВерсий(
        ["fsck", "--strict", "--no-reflogs", "--unreachable", "--no-progress"],
        в: рабочаяКопия
      )
      guard рабочаяКопияЧиста, проверкаОбъектов.isEmpty else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Рабочая копия не чиста либо содержит недостижимый объект: \(имя); "
            + "чиста=\(рабочаяКопияЧиста); fsck=\(проверкаОбъектов)."
        )
      }
      чистыеРабочиеКопии.append(имя)
      проверенныеРепозитории.append(имя)
    }
    let инвентарь = НормализованныйИнвентарьАвтономнойПриёмки(
      файлыСостояния: фактическиеФайлыСостояния,
      ссылкиРепозиториев: ссылкиРепозиториев,
      чистыеРабочиеКопии: чистыеРабочиеКопии,
      проверенныеРепозитории: проверенныеРепозитории.sorted()
    )
    return ДоказательствоГраницСбоев(
      точки: точки,
      промежуточныеФайлыУчтены: true,
      точныйПовторПослеУспешнойСравнительнойЗамены: точныйПовторИнтеграции,
      возобновляемоеСостояниеПослеСравнительнойЗамены:
        try сбои.состояние(.интеграция),
      хэшИнвентаря: try хэшАвтономнойПриёмки(инвентарь)
    )
  }

  fileprivate func проверитьСвежиеКлоны(
    сборка: URL,
    вершинаСборки: String,
    ожидаемоеЯдро: String,
    ожидаемыйРебёнок: String,
    ожидаемаяОчередьРебёнка: ПаспортОчередиКомпонентаАвтономнойПриёмки
  ) throws -> ДоказательствоСвежегоВосстановления {
    let локальнаяРабочаяКопия = корень.appending(path: "свежая-сборка")
    _ = try выполнитьКомандуКонтроляВерсий(
      ["clone", "--no-checkout", сборка.path, локальнаяРабочаяКопия.path], в: корень)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["checkout", "--detach", вершинаСборки], в: локальнаяРабочаяКопия)
    _ = try выполнитьКомандуКонтроляВерсий(
      [
        "-c", "protocol.file.allow=always", "submodule", "update", "--init", "--",
        "Компоненты/ядро", "Компоненты/дочернее-ответвление",
      ],
      в: локальнаяРабочаяКопия
    )
    let ядро = локальнаяРабочаяКопия.appending(path: "Компоненты/ядро")
    let ребёнок = локальнаяРабочаяКопия.appending(
      path: "Компоненты/дочернее-ответвление"
    )
    let сборкаОтсоединена =
      !(try командаКонтроляВерсийУспешна(
        ["symbolic-ref", "--quiet", "HEAD"], в: локальнаяРабочаяКопия))
    let ядроОтсоединено =
      !(try командаКонтроляВерсийУспешна(["symbolic-ref", "--quiet", "HEAD"], в: ядро))
    let ребёнокОтсоединён =
      !(try командаКонтроляВерсийУспешна(["symbolic-ref", "--quiet", "HEAD"], в: ребёнок))
    let фактическоеЯдро = try текстКомандыКонтроляВерсий(["rev-parse", "HEAD"], в: ядро)
    let фактическийРебёнок = try текстКомандыКонтроляВерсий(["rev-parse", "HEAD"], в: ребёнок)
    let снимкиОтсоединены =
      сборкаОтсоединена && ядроОтсоединено && ребёнокОтсоединён
      && фактическоеЯдро == ожидаемоеЯдро
      && фактическийРебёнок == ожидаемыйРебёнок
    let очередьЯдра = try JSONDecoder().decode(
      ПаспортОчередиКомпонентаАвтономнойПриёмки.self,
      from: Data(contentsOf: ядро.appending(path: "Планирование/очередь-ядра.json"))
    )
    let очередьРебёнка = try JSONDecoder().decode(
      ПаспортОчередиКомпонентаАвтономнойПриёмки.self,
      from: Data(contentsOf: ребёнок.appending(path: "Планирование/очередь-форка.json"))
    )
    let очереди =
      очередьЯдра.идентификатор == "очередь.ядро"
      && очередьЯдра.поколение == "поколение.ядро.1"
      && очередьЯдра.владелец == nil
      && очередьЯдра.следующийНомер == 1
      && очередьЯдра.ожидающиеБилеты.isEmpty
      && очередьРебёнка == ожидаемаяОчередьРебёнка
    return ДоказательствоСвежегоВосстановления(
      снимкиОтсоединены: снимкиОтсоединены, очереди: очереди)
  }
}

extension СтендАвтономнойПриёмкиПараллельныхПодузлов {
  fileprivate func записать(_ данные: Data, по адрес: URL) throws {
    try эффекты.зарегистрироватьЗапись(адрес)
    try файловаяСистема.createDirectory(
      at: адрес.deletingLastPathComponent(),
      withIntermediateDirectories: true
    )
    try данные.write(to: адрес)
  }

  fileprivate func записатьАтомарно(_ данные: Data, по адрес: URL) throws {
    try эффекты.зарегистрироватьЗапись(адрес)
    try файловаяСистема.createDirectory(
      at: адрес.deletingLastPathComponent(),
      withIntermediateDirectories: true
    )
    try данные.write(to: адрес, options: .atomic)
  }

  fileprivate func снимокРабочейКопии(_ репозиторий: URL) throws -> String {
    [
      try текстКомандыКонтроляВерсий(["rev-parse", "HEAD"], в: репозиторий),
      try текстКомандыКонтроляВерсий(["rev-parse", "HEAD^{tree}"], в: репозиторий),
      try текстКомандыКонтроляВерсий(
        ["status", "--porcelain=v1", "--untracked-files=all"], в: репозиторий),
    ].joined(separator: "\n")
  }

  @discardableResult
  fileprivate func выполнитьКомандуКонтроляВерсий(
    _ аргументы: [String],
    в каталог: URL,
    дата: String? = nil,
    ввод: Data? = nil
  ) throws -> String {
    try эффекты.проверитьКомандуКонтроляВерсий(аргументы, в: каталог)
    let процесс = Process()
    процесс.executableURL = WritingSubnodeSystemRuntime.gitExecutableURL
    процесс.arguments =
      [
        "-c", "protocol.file.allow=always",
        "-c", "core.autocrlf=false",
        "-c", "core.filemode=false",
      ] + аргументы
    var среда = [
      "PATH": ProcessInfo.processInfo.environment["PATH"] ?? "",
      "LC_ALL": "C",
      "LANG": "C",
      "TZ": "UTC",
      "GIT_CONFIG_NOSYSTEM": "1",
      "GIT_CONFIG_GLOBAL": WritingSubnodeSystemRuntime.nullDevicePath,
      "GIT_TERMINAL_PROMPT": "0",
      "GIT_AUTHOR_NAME": "Автономная фикстура FUM",
      "GIT_AUTHOR_EMAIL": "автономная-фикстура@fum.invalid",
      "GIT_COMMITTER_NAME": "Автономная фикстура FUM",
      "GIT_COMMITTER_EMAIL": "автономная-фикстура@fum.invalid",
    ]
    if let дата {
      среда["GIT_AUTHOR_DATE"] = дата
      среда["GIT_COMMITTER_DATE"] = дата
    }
    процесс.environment = среда
    процесс.currentDirectoryURL = каталог
    let канал = Pipe()
    процесс.standardOutput = канал
    процесс.standardError = канал
    let каналВвода: Pipe?
    if ввод != nil {
      let созданныйКанал = Pipe()
      процесс.standardInput = созданныйКанал
      каналВвода = созданныйКанал
    } else {
      процесс.standardInput = FileHandle.nullDevice
      каналВвода = nil
    }
    try процесс.run()
    if let ввод, let каналВвода {
      try каналВвода.fileHandleForWriting.write(contentsOf: ввод)
      try каналВвода.fileHandleForWriting.close()
    }
    процесс.waitUntilExit()
    let данные = канал.fileHandleForReading.readDataToEndOfFile()
    let вывод = String(decoding: данные, as: UTF8.self)
    guard процесс.terminationStatus == 0 else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.командаКонтроляВерсий(
        аргументы,
        процесс.terminationStatus,
        вывод
      )
    }
    return вывод.trimmingCharacters(in: .whitespacesAndNewlines)
  }

  fileprivate func текстКомандыКонтроляВерсий(_ аргументы: [String], в каталог: URL) throws
    -> String
  {
    try выполнитьКомандуКонтроляВерсий(аргументы, в: каталог)
  }

  fileprivate func вершинаСсылкиИлиОтсутствие(
    _ ссылка: String,
    в каталог: URL
  ) throws -> String? {
    do {
      _ = try текстКомандыКонтроляВерсий(
        ["symbolic-ref", "--quiet", ссылка],
        в: каталог
      )
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Ожидалась прямая, а не символическая ссылка: \(ссылка)."
      )
    } catch let
      ОшибкаАвтономнойПриёмкиПараллельныхПодузлов
      .командаКонтроляВерсий(_, код, _) where код == 1
    {
      // Прямая или отсутствующая ссылка: дальше различает `rev-parse`.
    }
    do {
      return try текстКомандыКонтроляВерсий(
        ["rev-parse", "--verify", "--quiet", ссылка],
        в: каталог
      )
    } catch let
      ОшибкаАвтономнойПриёмкиПараллельныхПодузлов
      .командаКонтроляВерсий(_, код, _) where код == 1
    {
      return nil
    }
  }

  fileprivate func командаКонтроляВерсийУспешна(
    _ аргументы: [String],
    в каталог: URL,
    ввод: Data? = nil
  ) throws -> Bool {
    do {
      _ = try выполнитьКомандуКонтроляВерсий(
        аргументы,
        в: каталог,
        ввод: ввод
      )
      return true
    } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.командаКонтроляВерсий {
      return false
    }
  }
}

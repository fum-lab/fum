private final class АвтономныйРеестрОркестрации {
  private let адрес: URL
  private var состояние: СостояниеАвтономнойОркестрации

  init(адрес: URL, логическийФорк: String, поколение: String) throws {
    self.адрес = адрес
    состояние = СостояниеАвтономнойОркестрации(
      версия: 1,
      логическийФорк: логическийФорк,
      поколение: поколение,
      исходныеОтветы: [:],
      доказательстваСреды: [:],
      поколениеАктивировано: false,
      родительскийВладелец: "сеанс.родитель.ответвление.1",
      родительскоеПоколениеСеанса: 1,
      квитанцииДопуска: [:],
      билеты: [],
      максимумВладельцевОдногоРебёнка: 0,
      идентификаторСеансаМодератора: nil,
      хэшПаспортаМодерации: nil
    )
    try сохранить()
  }

  init(восстанавливая адрес: URL) throws {
    self.адрес = адрес
    состояние = try JSONDecoder().decode(
      СостояниеАвтономнойОркестрации.self,
      from: Data(contentsOf: адрес)
    )
  }

  func сохранитьОтвет(
    _ ответ: СостояниеНачальногоОтветаСреды,
    сторона: String,
    доказательство: СвидетельствоПоддельнойСреды? = nil
  ) throws {
    guard !состояние.поколениеАктивировано else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Активированное поколение не принимает новый исходный ответ."
      )
    }
    guard (ответ == .подтверждён) == (доказательство != nil) else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Подтверждённый ответ среды обязан иметь точное доказательство."
      )
    }
    состояние.исходныеОтветы[сторона] = ответ
    if let доказательство {
      состояние.доказательстваСреды[сторона] = доказательство
    }
    try сохранить()
  }

  func попытатьсяАктивировать() throws -> Bool {
    let ответы = состояние.исходныеОтветы
    let доказательства = состояние.доказательстваСреды
    let допустимо =
      ответы["левая"] == .подтверждён
      && ответы["правая"] == .подтверждён
      && доказательства.count == 2
      && Set(доказательства.values.map(\.идентификаторЗадачи)).count == 2
      && Set(доказательства.values.map(\.идентификаторСреды)).count == 2
      && доказательства.values.allSatisfy {
        !$0.хэшКвитанции.isEmpty && !$0.хэшПривязки.isEmpty && !$0.хэшКонверта.isEmpty
      }
    if допустимо { состояние.поколениеАктивировано = true }
    try сохранить()
    return допустимо
  }

  func допустить(
    сторона: String,
    ребёнок: String,
    репозиторий: String,
    ссылка: String,
    рабочаяКопия: String,
    роль: String,
    маршрут: String,
    хэшПолномочий: String,
    владелец: String
  ) throws -> КвитанцияДочернегоДопуска {
    guard состояние.поколениеАктивировано,
      let доказательствоСреды = состояние.доказательстваСреды[сторона],
      состояние.квитанцииДопуска[ребёнок] == nil,
      !состояние.квитанцииДопуска.values.contains(where: {
        $0.идентификаторРепозитория == репозиторий
          || $0.рабочаяСсылка == ссылка
          || $0.идентификаторРабочейКопии == рабочаяКопия
      })
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Дочерний FIFO-допуск не является единственным."
      )
    }
    let нагрузка = [
      состояние.поколение, сторона, ребёнок, репозиторий, ссылка, рабочаяКопия,
      роль, маршрут, доказательствоСреды.идентификаторЗадачи,
      доказательствоСреды.идентификаторСреды, доказательствоСреды.хэшКвитанции,
      доказательствоСреды.хэшПривязки, доказательствоСреды.хэшКонверта,
      хэшПолномочий, владелец,
    ]
    let квитанция = КвитанцияДочернегоДопуска(
      поколение: состояние.поколение,
      сторона: сторона,
      идентификаторРебёнка: ребёнок,
      идентификаторРепозитория: репозиторий,
      рабочаяСсылка: ссылка,
      идентификаторРабочейКопии: рабочаяКопия,
      роль: роль,
      маршрут: маршрут,
      идентификаторЗадачиСреды: доказательствоСреды.идентификаторЗадачи,
      идентификаторСреды: доказательствоСреды.идентификаторСреды,
      хэшКвитанцииСреды: доказательствоСреды.хэшКвитанции,
      хэшПривязкиСреды: доказательствоСреды.хэшПривязки,
      хэшКонвертаСреды: доказательствоСреды.хэшКонверта,
      хэшПрофиляПолномочий: хэшПолномочий,
      идентификаторВладельца: владелец,
      хэшКвитанции: try хэшАвтономнойПриёмки(нагрузка)
    )
    состояние.квитанцииДопуска[ребёнок] = квитанция
    состояние.билеты.append(
      БилетДочернейОчереди(
        идентификатор: "билет.\(ребёнок).владелец",
        идентификаторРебёнка: ребёнок,
        идентификаторСеанса: владелец,
        состояние: .владеет
      )
    )
    состояние.максимумВладельцевОдногоРебёнка = max(
      состояние.максимумВладельцевОдногоРебёнка,
      числоВладельцев(ребёнок)
    )
    try сохранить()
    return квитанция
  }

  func добавитьОжидающееПродолжение(ребёнок: String, сеанс: String) throws {
    guard состояние.квитанцииДопуска[ребёнок] != nil else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Продолжение не связано с допущенным ребёнком."
      )
    }
    состояние.билеты.append(
      БилетДочернейОчереди(
        идентификатор: "билет.\(ребёнок).продолжение",
        идентификаторРебёнка: ребёнок,
        идентификаторСеанса: сеанс,
        состояние: .ожидает
      )
    )
    состояние.максимумВладельцевОдногоРебёнка = max(
      состояние.максимумВладельцевОдногоРебёнка,
      числоВладельцев(ребёнок)
    )
    try сохранить()
  }

  func завершитьВладение(ребёнок: String, владелец: String) throws {
    guard
      let номер = состояние.билеты.firstIndex(where: {
        $0.идентификаторРебёнка == ребёнок
          && $0.идентификаторСеанса == владелец
          && $0.состояние == .владеет
      })
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Терминализация не нашла точного дочернего владельца."
      )
    }
    состояние.билеты[номер].состояние = .завершён
    try сохранить()
  }

  func закрепитьПаспортМодерации(
    _ паспорт: ПаспортМодерацииКорневойЦепочки,
    ожидаемыйХэш: String
  ) throws {
    guard состояние.родительскийВладелец != nil,
      состояние.хэшПаспортаМодерации == nil,
      паспорт.идентификаторРодителяМодератора == состояние.логическийФорк,
      паспорт.поколениеНазначения == состояние.поколение,
      паспорт.правыйРезультат != nil,
      try паспорт.каноническийХэш() == ожидаемыйХэш
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Паспорт модерации не закреплён до освобождения родителя."
      )
    }
    состояние.хэшПаспортаМодерации = ожидаемыйХэш
    try сохранить()
  }

  func освободитьРодителя(владелец: String) throws {
    guard состояние.родительскийВладелец == владелец,
      состояние.билеты.allSatisfy({ $0.состояние != .владеет }),
      состояние.хэшПаспортаМодерации != nil
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Родитель освобождается только после точного терминала детей."
      )
    }
    состояние.родительскийВладелец = nil
    try сохранить()
  }

  func восстановитьМодератора(
    по паспорт: ПаспортМодерацииКорневойЦепочки,
    ожидаемыйХэш: String
  ) throws {
    guard состояние.логическийФорк == паспорт.идентификаторРодителяМодератора,
      состояние.поколение == паспорт.поколениеНазначения,
      состояние.родительскийВладелец == nil,
      состояние.идентификаторСеансаМодератора == nil,
      состояние.хэшПаспортаМодерации == ожидаемыйХэш,
      try паспорт.каноническийХэш() == ожидаемыйХэш,
      !паспорт.идентификаторПопытки.isEmpty,
      паспорт.правыйРезультат != nil,
      паспорт.интеграционнаяВершина == nil,
      паспорт.родителиИнтеграционнойВершины.isEmpty
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Модератор не прошёл ограждение fork и поколения сеанса."
      )
    }
    состояние.родительскоеПоколениеСеанса += 1
    состояние.идентификаторСеансаМодератора = паспорт.идентификаторПопытки
    try сохранить()
  }

  func паспортОчереди(ребёнок: String) throws
    -> ПаспортОчередиКомпонентаАвтономнойПриёмки
  {
    guard состояние.квитанцииДопуска[ребёнок] != nil else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Нельзя вывести очередь неизвестного ребёнка."
      )
    }
    let билеты = состояние.билеты.filter { $0.идентификаторРебёнка == ребёнок }
    let владельцы = билеты.filter { $0.состояние == .владеет }
    guard владельцы.count <= 1 else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Снимок очереди обнаружил более одного владельца."
      )
    }
    let проекция = ПроекцияСостоянияДочернейОчередиАвтономнойПриёмки(
      поколение: состояние.поколение,
      идентификаторРебёнка: ребёнок,
      билеты: билеты.sorted {
        ($0.идентификатор, $0.идентификаторСеанса)
          < ($1.идентификатор, $1.идентификаторСеанса)
      }
    )
    return ПаспортОчередиКомпонентаАвтономнойПриёмки(
      версия: 1,
      идентификатор: "очередь." + ребёнок,
      поколение: состояние.поколение,
      владелец: владельцы.first?.идентификаторСеанса,
      следующийНомер: билеты.count + 1,
      ожидающиеБилеты: билеты.filter { $0.состояние == .ожидает }
        .map(\.идентификаторСеанса).sorted(),
      хэшСостоянияИсточника: try хэшАвтономнойПриёмки(проекция)
    )
  }

  var числоДопусков: Int { состояние.квитанцииДопуска.count }
  var числоИсходныхОтветов: Int { состояние.исходныеОтветы.count }
  var активировано: Bool { состояние.поколениеАктивировано }
  var родительОсвобождён: Bool { состояние.родительскийВладелец == nil }
  var модератор: String? { состояние.идентификаторСеансаМодератора }
  var максимумВладельцев: Int { состояние.максимумВладельцевОдногоРебёнка }
  var ожидающееПродолжениеЯвляетсяВладельцем: Bool {
    состояние.билеты.contains { билет in
      билет.идентификатор.contains("продолжение") && билет.состояние == .владеет
    }
  }

  private func числоВладельцев(_ ребёнок: String) -> Int {
    состояние.билеты.filter {
      $0.идентификаторРебёнка == ребёнок && $0.состояние == .владеет
    }.count
  }

  private func сохранить() throws {
    try FileManager.default.createDirectory(
      at: адрес.deletingLastPathComponent(),
      withIntermediateDirectories: true
    )
    try каноническиеДанныеАвтономнойПриёмки(состояние).write(to: адрес, options: .atomic)
  }
}

private func каноническиеДанныеАвтономнойПриёмки<Значение: Encodable>(
  _ значение: Значение
) throws -> Data {
  let кодировщик = JSONEncoder()
  кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
  return try кодировщик.encode(значение)
}

private func хэшАвтономнойПриёмки(_ данные: Data) -> String {
  "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}

private func хэшАвтономнойПриёмки<Значение: Encodable>(_ значение: Значение) throws -> String {
  хэшАвтономнойПриёмки(try каноническиеДанныеАвтономнойПриёмки(значение))
}

private final class БарьерПараллельныхРолевыхЦепочек: @unchecked Sendable {
  private let условие = NSCondition()
  private var числоПрибывших = 0
  private var числоАктивных = 0
  private var отменён = false
  private(set) var максимумАктивных = 0

  func войти() throws {
    условие.lock()
    defer { условие.unlock() }
    guard !отменён else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Параллельный барьер отменён до входа обеих цепочек."
      )
    }
    числоПрибывших += 1
    числоАктивных += 1
    максимумАктивных = max(максимумАктивных, числоАктивных)
    if числоПрибывших == 2 {
      условие.broadcast()
    } else {
      let крайнийСрок = Date().addingTimeInterval(30)
      while числоПрибывших < 2 && !отменён {
        if !условие.wait(until: крайнийСрок) {
          отменён = true
          условие.broadcast()
        }
      }
    }
    guard !отменён else {
      числоАктивных -= 1
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Параллельный барьер не получил обе допущенные цепочки."
      )
    }
  }

  func выйти() {
    условие.lock()
    числоАктивных -= 1
    условие.unlock()
  }

  func отменить() {
    условие.lock()
    отменён = true
    условие.broadcast()
    условие.unlock()
  }
}

private final class АвтономныйРаспределительРесурсов: @unchecked Sendable {
  private let условие = NSCondition()
  private var активныеРесурсы: Set<String> = []
  private var числоАктивных = 0
  private(set) var максимумАктивных = 0

  func сДопуском<Результат>(
    ресурс: String,
    приОжидании: (() -> Void)? = nil,
    _ тело: () throws -> Результат
  ) rethrows -> Результат {
    условие.lock()
    var ожиданиеОбъявлено = false
    while активныеРесурсы.contains(ресурс) {
      if !ожиданиеОбъявлено {
        условие.unlock()
        приОжидании?()
        условие.lock()
        ожиданиеОбъявлено = true
      }
      условие.wait()
    }
    активныеРесурсы.insert(ресурс)
    числоАктивных += 1
    максимумАктивных = max(максимумАктивных, числоАктивных)
    условие.unlock()
    defer {
      условие.lock()
      активныеРесурсы.remove(ресурс)
      числоАктивных -= 1
      условие.broadcast()
      условие.unlock()
    }
    return try тело()
  }
}

private final class ХранилищеРезультатовРолевыхЦепочек: @unchecked Sendable {
  private let замок = NSLock()
  private var результаты: [Int: Result<СвидетельствоДочернейРолевойЦепочки, Error>] = [:]

  func сохранить(
    _ результат: Result<СвидетельствоДочернейРолевойЦепочки, Error>,
    номер: Int
  ) {
    замок.lock()
    результаты[номер] = результат
    замок.unlock()
  }

  func получить(_ номер: Int) throws -> СвидетельствоДочернейРолевойЦепочки {
    замок.lock()
    let результат = результаты[номер]
    замок.unlock()
    guard let результат else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Дочерняя цепочка не вернула результат."
      )
    }
    return try результат.get()
  }
}

private final class РеестрЭффектовАвтономнойПриёмки: @unchecked Sendable {
  private let замок = NSLock()
  private let корень: URL
  private var нарушения: [String] = []
  private var журнал: [String] = []
  private var числоЗапусковПроцессов = 0
  private var числоЗаблокированныхПроб = 0

  init(корень: URL) {
    self.корень = корень.standardizedFileURL.resolvingSymlinksInPath()
  }

  func проверитьКомандуКонтроляВерсий(
    _ аргументы: [String],
    в каталог: URL
  ) throws {
    let строка = аргументы.joined(separator: " ").lowercased()
    let запрещённые = ["http://", "https://", "ssh://", "git@", "--upload-pack", "--receive-pack"]
    let найденные = запрещённые.filter(строка.contains)
    if !найденные.isEmpty {
      замок.lock()
      числоЗаблокированныхПроб += 1
      журнал.append("заблокирована-сетевая-команда")
      замок.unlock()
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Сетевая команда Git заблокирована до запуска процесса."
      )
    }
    let каноническийКаталог = каталог.standardizedFileURL.resolvingSymlinksInPath()
    let корневойПрефикс = корень.path.hasSuffix("/") ? корень.path : корень.path + "/"
    let каталогЛокален =
      каноническийКаталог.path == корень.path
      || каноническийКаталог.path.hasPrefix(корневойПрефикс)
    let нелокальныеПути = аргументы.filter { $0.hasPrefix("/") }.filter { значение in
      let путь = URL(fileURLWithPath: значение).standardizedFileURL
        .resolvingSymlinksInPath().path
      return путь != корень.path && !путь.hasPrefix(корневойПрефикс)
    }
    guard каталогЛокален, нелокальныеПути.isEmpty else {
      замок.lock()
      нарушения.append("выход-за-корень-стенда")
      замок.unlock()
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Git-эффект вышел за канонический корень автономного стенда."
      )
    }
    замок.lock()
    числоЗапусковПроцессов += 1
    журнал.append(
      "локальная-команда-контроля-версий:\(аргументы.first ?? "неизвестно")"
    )
    замок.unlock()
  }

  func зарегистрироватьЗапись(_ адрес: URL) throws {
    let путь = адрес.standardizedFileURL.resolvingSymlinksInPath().path
    let префикс = корень.path.hasSuffix("/") ? корень.path : корень.path + "/"
    guard путь.hasPrefix(префикс) else {
      замок.lock()
      нарушения.append("запись-вне-корня-стенда")
      замок.unlock()
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Файловая запись вышла за корень автономного стенда."
      )
    }
    замок.lock()
    журнал.append("локальная-запись")
    замок.unlock()
  }

  func зарегистрироватьОфициальныйКонтур(
    источник: URL,
    цель: URL
  ) throws {
    try проверитьЛокальныеАдреса([источник, цель])
    замок.lock()
    журнал.append("официальный-корневой-контур")
    замок.unlock()
  }

  func доказатьПредварительнуюБлокировкуСети(в каталог: URL) throws -> Bool {
    замок.lock()
    let запусковДо = числоЗапусковПроцессов
    let блокировокДо = числоЗаблокированныхПроб
    замок.unlock()
    do {
      try проверитьКомандуКонтроляВерсий(
        ["ls-remote", "https://example.invalid/fum.git"],
        в: каталог
      )
      return false
    } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение {
      замок.lock()
      let результат =
        числоЗапусковПроцессов == запусковДо
        && числоЗаблокированныхПроб == блокировокДо + 1
      замок.unlock()
      return результат
    }
  }

  private func проверитьЛокальныеАдреса(_ адреса: [URL]) throws {
    let префикс = корень.path.hasSuffix("/") ? корень.path : корень.path + "/"
    guard
      адреса.allSatisfy({ адрес in
        let путь = адрес.standardizedFileURL.resolvingSymlinksInPath().path
        return путь == корень.path || путь.hasPrefix(префикс)
      })
    else {
      замок.lock()
      нарушения.append("официальный-контур-вне-корня")
      замок.unlock()
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Официальный контур вышел за автономный корень."
      )
    }
  }

  var доказательнаяГраницаЗамкнута: Bool {
    замок.lock()
    let результат =
      !журнал.isEmpty
      && числоЗапусковПроцессов > 0
      && числоЗаблокированныхПроб == 1
      && нарушения.isEmpty
    замок.unlock()
    return результат
  }

  var запрещённыеЭффекты: [String] {
    замок.lock()
    let результат = Array(Set(нарушения)).sorted()
    замок.unlock()
    return результат
  }
}

private final class РеестрДоказательствСбоевАвтономнойПриёмки: @unchecked Sendable {
  private let корень: URL

  init(корень: URL) {
    self.корень = корень
  }

  func следуетПроверить(_ точка: ТочкаСбояАвтономнойПриёмки) -> Bool {
    !FileManager.default.fileExists(atPath: адресТочки(точка).path)
  }

  func запланировать(
    _ точка: ТочкаСбояАвтономнойПриёмки,
    намерение: String
  ) throws {
    let адрес = адресТочки(точка)
    if FileManager.default.fileExists(atPath: адрес.path) {

  init(
    восстанавливая существующийКорень: URL,
    эффекты: РеестрЭффектовАвтономнойПриёмки
  ) throws {
    guard FileManager.default.fileExists(atPath: существующийКорень.path) else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Новый сеанс не нашёл долговечный корень автономного стенда."
      )
    }
    корень = существующийКорень
    удалятьКорень = false
    self.эффекты = эффекты
    сбои = РеестрДоказательствСбоевАвтономнойПриёмки(
      корень: существующийКорень.appending(path: "состояние/сбои")
    )
  }

  deinit {
    if удалятьКорень {
      try? файловаяСистема.removeItem(at: корень)
    }
  }

  fileprivate func новыйСеансВосстановления() throws
    -> СтендАвтономнойПриёмкиПараллельныхПодузлов
  {
    try СтендАвтономнойПриёмкиПараллельныхПодузлов(
      восстанавливая: корень,
      эффекты: эффекты
    )
  }

  func выполнить() throws -> СнимокАвтономнойПриёмкиПараллельныхПодузлов {
    let ядро = корень.appending(path: "ядро.git", directoryHint: .isDirectory)
    let родительскийФорк = корень.appending(
      path: "родительское-ответвление.git",
      directoryHint: .isDirectory
    )
    let левыйФорк = корень.appending(
      path: "ребёнок-поставщик.git",
      directoryHint: .isDirectory
    )
    let правыйФорк = корень.appending(
      path: "ребёнок-критик.git",
      directoryHint: .isDirectory
    )
    let сборка = корень.appending(path: "сборка.git", directoryHint: .isDirectory)

    let база = try создатьЯдро(голыйРепозиторий: ядро)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["clone", "--bare", ядро.path, родительскийФорк.path], в: корень)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["clone", "--bare", родительскийФорк.path, левыйФорк.path], в: корень)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["clone", "--bare", родительскийФорк.path, правыйФорк.path], в: корень)

    let родительскаяРабочаяКопия = корень.appending(
      path: "родительская-рабочая-копия"
    )
    _ = try выполнитьКомандуКонтроляВерсий(
      ["clone", родительскийФорк.path, родительскаяРабочаяКопия.path], в: корень)
    let снимокРодителяДо = try снимокРабочейКопии(родительскаяРабочаяКопия)

    let базоваяСборка = try создатьСборку(
      голыйРепозиторий: сборка,
      базоваяВершинаЯдра: база,
      базоваяВершинаРебёнка: база
    )
    let логическийФорк = "ответвление.родитель.оценка-навыка"
    let поколение = "поколение.параллельные-универсальные-подузлы.1"
    let описания = [описаниеРолевойЦепочки(номер: 0), описаниеРолевойЦепочки(номер: 1)]
    let официальноеПоколение = try подготовитьОфициальноеПоколениеАвтономнойПриёмки(
      поколение: поколение,
      база: база,
      описания: описания,
      левыйФорк: левыйФорк,
      правыйФорк: правыйФорк
    )
    guard let левыйОфициальныйДопуск = официальноеПоколение.допуски[.левая],
      let правыйОфициальныйДопуск = официальноеПоколение.допуски[.правая]
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Официальный реестр не вернул точную пару допусков."
      )
    }
    let леваяРабочаяКопия = левыйОфициальныйДопуск.рабочаяКопия
    let праваяРабочаяКопия = правыйОфициальныйДопуск.рабочаяКопия
    let частичныйОтветСреды = try ФикстурыКорневогоРеестраЗапусков.неполныйОтвет()
    let неизвестныйОтветСреды = try ФикстурыКорневогоРеестраЗапусков.потерянныйПервыйОтвет()
    let максимумКонфликтующихЗапусков = try доказатьКонфликтРесурсовВТомЖеРеестре(
      реестр: официальноеПоколение.реестр.значение,
      база: база,
      левыйФорк: левыйФорк,
      правыйФорк: правыйФорк
    )
    guard частичныйОтветСреды.числоАктиваций == 0,
      неизвестныйОтветСреды.числоАктиваций == 0
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Fake-host или ресурсный допуск не подтвердил ограждённый запуск."
      )
    }

    let доказательстваСреды = официальноеПоколение.доказательстваСреды
    let частичныйРеестр = try АвтономныйРеестрОркестрации(
      адрес: корень.appending(path: "состояние/оркестрация/частичный.json"),
      логическийФорк: логическийФорк,
      поколение: поколение
    )
    try частичныйРеестр.сохранитьОтвет(
      .подтверждён,
      сторона: "левая",
      доказательство: доказательстваСреды["левая"]
    )
    try частичныйРеестр.сохранитьОтвет(.неполон, сторона: "правая")
    let частичныйЗапускАктивировалПоколение = try частичныйРеестр.попытатьсяАктивировать()

    let неизвестныйРеестр = try АвтономныйРеестрОркестрации(
      адрес: корень.appending(path: "состояние/оркестрация/неизвестный.json"),
      логическийФорк: логическийФорк,
      поколение: поколение
    )
    try неизвестныйРеестр.сохранитьОтвет(
      .подтверждён,
      сторона: "левая",
      доказательство: доказательстваСреды["левая"]
    )
    try неизвестныйРеестр.сохранитьОтвет(.неизвестен, сторона: "правая")
    let неизвестныйЗапускАктивировалПоколение = try неизвестныйРеестр.попытатьсяАктивировать()

    let адресТочногоРеестра = корень.appending(
      path: "состояние/оркестрация/точный.json"
    )
    var точныйРеестр = try АвтономныйРеестрОркестрации(
      адрес: адресТочногоРеестра,
      логическийФорк: логическийФорк,
      поколение: поколение
    )
    let допусковДоАктивации = официальноеПоколение.допусковДоАктивации
    let хэшПолномочий = try хэшАвтономнойПриёмки(
      ["собственный-репозиторий-и-ссылка", "два-содержательных-шага", "без-сети"].sorted()
    )
    var предактивационныйДопускОтклонён = false
    do {
      let описание = описания[0]
      _ = try точныйРеестр.допустить(
        сторона: описание.сторона,
        ребёнок: описание.идентификаторРебёнка,
        репозиторий: описание.идентификаторРепозитория,
        ссылка: описание.рабочаяСсылка,
        рабочаяКопия: описание.идентификаторРабочейКопии,
        роль: описание.роль,
        маршрут: описание.маршрут,
        хэшПолномочий: хэшПолномочий,
        владелец: описание.идентификаторВладельца
      )
    } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение {
      предактивационныйДопускОтклонён = true
    }
    guard предактивационныйДопускОтклонён else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Реестр выдал дочерний допуск до активации пары."
      )
    }
    let намерениеСбояЗапуска = "сохранить_точную_пару_ответов_среды"
    let наблюдениеСбояЗапуска = "ответы_среды_сохранены_активация_ожидается"
    try сбои.запланировать(.запуск, намерение: намерениеСбояЗапуска)
    try точныйРеестр.сохранитьОтвет(
      .подтверждён,
      сторона: "левая",
      доказательство: доказательстваСреды["левая"]
    )
    try точныйРеестр.сохранитьОтвет(
      .подтверждён,
      сторона: "правая",
      доказательство: доказательстваСреды["правая"]
    )
    do {
      try сбои.записатьЭффектИПотерятьОтвет(
        .запуск,
        намерение: намерениеСбояЗапуска,
        наблюдение: наблюдениеСбояЗапуска
      )
    } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.намеренноеПрерывание {
      let новыйСеанс = try новыйСеансВосстановления()
      точныйРеестр = try АвтономныйРеестрОркестрации(
        восстанавливая: адресТочногоРеестра
      )
      try новыйСеанс.сбои.восстановитьПослеПотериОтвета(
        .запуск,
        намерение: намерениеСбояЗапуска,
        наблюдение: наблюдениеСбояЗапуска
      ) {
        точныйРеестр.числоИсходныхОтветов == 2
          && точныйРеестр.числоДопусков == 0
          && !точныйРеестр.активировано
      }
    }
    guard try точныйРеестр.попытатьсяАктивировать() else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Точный долговечный реестр не активировал подтверждённую пару."
      )
    }
    let квитанции = try описания.map { описание in
      try точныйРеестр.допустить(
        сторона: описание.сторона,
        ребёнок: описание.идентификаторРебёнка,
        репозиторий: описание.идентификаторРепозитория,
        ссылка: описание.рабочаяСсылка,
        рабочаяКопия: описание.идентификаторРабочейКопии,
        роль: описание.роль,
        маршрут: описание.маршрут,
        хэшПолномочий: хэшПолномочий,
        владелец: описание.идентификаторВладельца
      )
    }
    try точныйРеестр.добавитьОжидающееПродолжение(
      ребёнок: описания[0].идентификаторРебёнка,
      сеанс: "сеанс.ребёнок.поставщик.продолжение"
    )
    var дубликатДочернегоВладельцаОтклонён = false
    do {
      _ = try точныйРеестр.допустить(
        сторона: описания[0].сторона,
        ребёнок: описания[0].идентификаторРебёнка,
        репозиторий: описания[0].идентификаторРепозитория,
        ссылка: описания[0].рабочаяСсылка,
        рабочаяКопия: описания[0].идентификаторРабочейКопии,
        роль: описания[0].роль,
        маршрут: описания[0].маршрут,
        хэшПолномочий: хэшПолномочий,
        владелец: "сеанс.ребёнок.поставщик.дубликат"
      )
    } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение {
      дубликатДочернегоВладельцаОтклонён = true
    }
    guard дубликатДочернегоВладельцаОтклонён else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Реестр принял второго владельца одной дочерней цепочки."
      )
    }

    let барьер = БарьерПараллельныхРолевыхЦепочек()
    let хранилище = ХранилищеРезультатовРолевыхЦепочек()
    let текущийСтенд = self
    let группаПотоков = DispatchGroup()
    for номер in 0..<2 {
      группаПотоков.enter()
      let поток = Thread {
        defer { группаПотоков.leave() }
        do {
          let результат = try текущийСтенд.выполнитьРолевуюЦепочку(
            описание: описания[номер],
            квитанция: квитанции[номер],
            база: база,
            рабочаяКопия: номер == 0 ? леваяРабочаяКопия : праваяРабочаяКопия,
            официальныйДопуск: номер == 0
              ? левыйОфициальныйДопуск : правыйОфициальныйДопуск,
            корневойРеестр: официальноеПоколение.реестр,
            барьер: барьер
          )
          хранилище.сохранить(.success(результат), номер: номер)
        } catch {
          барьер.отменить()
          хранилище.сохранить(.failure(error), номер: номер)
        }
      }
      поток.name = "автономная-ролевая-цепочка-\(номер + 1)"
      поток.start()
    }
    группаПотоков.wait()
    let дочерниеЦепочки = try [хранилище.получить(0), хранилище.получить(1)]
      .sorted { $0.идентификаторФорка < $1.идентификаторФорка }
    for описание in описания {
      try точныйРеестр.завершитьВладение(
        ребёнок: описание.идентификаторРебёнка,
        владелец: описание.идентификаторВладельца
      )
    }
    let поставщик = try обязательнаяЦепочка(
      роль: "поставщик_синтетического_навыка",
      в: дочерниеЦепочки
    )
    let критик = try обязательнаяЦепочка(
      роль: "критик_синтетического_навыка",
      в: дочерниеЦепочки
    )
    let вершиныДоМодерации = try дочерниеВершины(
      левыйФорк: левыйФорк,
      правыйФорк: правыйФорк,
      дочерниеЦепочки: дочерниеЦепочки
    )
    let хэшКритериевМодерации = try хэшАвтономнойПриёмки(
      ["синтетический-навык", "точный-диапазон", "автономная-граница"]
    )
    let паспортМодерации = ПаспортМодерацииКорневойЦепочки(
      идентификаторРодителяМодератора: логическийФорк,
      идентификаторПопытки: "сеанс.родитель.модератор.2",
      поколениеНазначения: поколение,
      идентификаторРодительскогоРепозитория: "репозиторий.ядро",
      провереннаяБаза: база,
      родительскаяРабочаяСсылка: "refs/heads/основная",
      ссылкаСостояния: "refs/fum/модерация/синтетический-навык",
      целеваяСсылкаИнтеграции: "refs/heads/основная",
      левыйРезультат: try заморозитьРезультатАвтономнойПриёмки(
        поставщик,
        в: левыйФорк
      ),
      правыйРезультат: try заморозитьРезультатАвтономнойПриёмки(
        критик,
        в: правыйФорк
      ),
      хэшКритериев: хэшКритериевМодерации,
      решение: .выбранЛевыйРезультат,
      интеграционнаяВершина: nil,
      родителиИнтеграционнойВершины: [],
      каноническийПутьРодительскогоРепозитория: ядро.standardizedFileURL
        .resolvingSymlinksInPath().path.precomposedStringWithCanonicalMapping
    )
    let данныеПаспортаМодерации = try паспортМодерации.каноническиеДанные()
    let хэшПаспортаМодерации = try паспортМодерации.каноническийХэш()
    let адресПаспортаМодерации = корень.appending(
      path: "состояние/паспорт-модерации.json"
    )
    try записатьАтомарно(
      данныеПаспортаМодерации,
      по: адресПаспортаМодерации
    )
    try точныйРеестр.закрепитьПаспортМодерации(
      паспортМодерации,
      ожидаемыйХэш: хэшПаспортаМодерации
    )
    try точныйРеестр.освободитьРодителя(
      владелец: "сеанс.родитель.ответвление.1"
    )
    let новыйСеансМодератора = try новыйСеансВосстановления()
    let восстановленныйРеестр = try АвтономныйРеестрОркестрации(
      восстанавливая: адресТочногоРеестра
    )
    let восстановленныйПаспортМодерации =
      try новыйСеансМодератора
      .восстановитьПаспортМодерацииАвтономнойПриёмки(
        по: адресПаспортаМодерации,
        ожидаемыйХэш: хэшПаспортаМодерации
      )
    try восстановленныйРеестр.восстановитьМодератора(
      по: восстановленныйПаспортМодерации,
      ожидаемыйХэш: хэшПаспортаМодерации
    )
    let восстановленныйХэшПаспортаМодерации =
      try восстановленныйПаспортМодерации
      .каноническийХэш()
    let снимокРодителяПосле = try снимокРабочейКопии(родительскаяРабочаяКопия)
    let манифест = try Data(
      contentsOf: леваяРабочаяКопия.appending(path: "Манифесты/синтетический-навык.json"))
    let диагностикаДоработки = try Data(
      contentsOf: праваяРабочаяКопия.appending(
        path: "Диагностика/требуется-доработка.md"
      )
    )
    let конвертПоставщика = try создатьКонверт(
      идентификатор: "предложение-слияния.синтетический-навык.принято",
      цепочка: поставщик,
      хэшМанифеста: хэшАвтономнойПриёмки(манифест)
    )
    let конвертКритика = try создатьКонверт(
      идентификатор: "предложение-слияния.синтетический-навык.доработка",
      цепочка: критик,
      хэшМанифеста: хэшАвтономнойПриёмки(диагностикаДоработки)
    )
    let конверты = try [конвертПоставщика, конвертКритика].map {
      try создатьИВосстановитьПредложение($0)
    }.sorted { $0.идентификатор < $1.идентификатор }

    let ожидаемаяОчередьРебёнка = try восстановленныйРеестр.паспортОчереди(
      ребёнок: описания[0].идентификаторРебёнка
    )
    let подготовленнаяСинхронизация = try подготовитьСинхронизациюРебёнка(
      форк: левыйФорк,
      вершинаЯдра: поставщик.вершина,
      очередь: ожидаемаяОчередьРебёнка
    )
    let принятоеРевью = try провестиОфициальноеРевью(
      цепочка: поставщик,
      другойРебёнок: критик,
      конверт: конвертПоставщика,
      исходныйРепозиторий: левыйФорк,
      репозиторийДругогоРебёнка: правыйФорк,
      ядро: ядро,
      исход: .принято,
      проверяющий: "проверяющий.синтетический-навык",
      актуальнаяВершина: поставщик.вершина,
      базоваяСборка: базоваяСборка,
      ожидаемаяРолеваяВершина: подготовленнаяСинхронизация.вершина,
      паспортМодерации: восстановленныйПаспортМодерации
    )
    let ревьюДоработки = try провестиОфициальноеРевью(

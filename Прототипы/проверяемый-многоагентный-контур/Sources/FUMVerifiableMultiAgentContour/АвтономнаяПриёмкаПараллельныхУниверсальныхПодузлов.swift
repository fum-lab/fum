  fileprivate func подготовитьОфициальноеПоколениеАвтономнойПриёмки(
    поколение: String,
    база: String,
    описания: [ОписаниеДочернейРолевойЦепочки],
    левыйФорк: URL,
    правыйФорк: URL
  ) throws -> ПодготовленноеОфициальноеПоколениеАвтономнойПриёмки {
    let стороны: [СторонаВетвевогоФорка] = [.левая, .правая]
    guard описания.count == стороны.count else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Официальный запуск требует точную пару описаний."
      )
    }
    let описанияПоСтороне = Dictionary(
      uniqueKeysWithValues: zip(стороны, описания).map { ($0.0, $0.1) }
    )
    let форки: [СторонаВетвевогоФорка: URL] = [
      .левая: левыйФорк,
      .правая: правыйФорк,
    ]
    let рабочиеКопии: [СторонаВетвевогоФорка: URL] = [
      .левая: корень.appending(path: "рабочая-копия-ребёнка-поставщика"),
      .правая: корень.appending(path: "рабочая-копия-ребёнка-критика"),
    ]
    let полномочия = Dictionary(
      uniqueKeysWithValues: стороны.map {
        ($0, ресурсныеПолномочияРолевойЦепочки(сторона: $0))
      }
    )
    let ветви = try стороны.map { сторона in
      guard let описание = описанияПоСтороне[сторона],
        let форк = форки[сторона],
        let рабочаяКопия = рабочиеКопии[сторона],
        let ресурсныеПолномочия = полномочия[сторона]
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Не собрана точная спецификация дочерней ветви."
        )
      }
      return СпецификацияВетвиКорневогоЗапуска(
        сторона: сторона,
        идентификаторНазначения: "назначение.\(сторона.rawValue)",
        роль: описание.роль,
        идентификаторРебёнка: "исполнитель.\(сторона.rawValue)",
        идентификаторФорка: описание.идентификаторРебёнка,
        идентификаторРепозитория: описание.идентификаторРепозитория,
        рабочаяСсылка: описание.рабочаяСсылка,
        идентификаторРабочейКопии: описание.идентификаторРабочейКопии,
        адресИсточника: форк,
        адресРабочейКопии: рабочаяКопия,
        идентификаторПопытки: "попытка.\(сторона.rawValue)",
        идентификаторШага: описание.маршрут,
        идентификаторПроекта: "проект.автономная-приёмка",
        ресурсныеПолномочия: [ресурсныеПолномочия]
      )
    }
    let реестр = try КорневойРеестрЗапусков(
      каталог: корень.appending(path: "состояние/корневой-реестр-запусков")
    )
    try реестр.подготовитьПоколение(
      СпецификацияПоколенияКорневогоЗапуска(
        идентификатор: поколение,
        исходнаяВершина: база,
        идентичностьКонтроллера: .недоступна,
        идентификаторКонтроллера: nil,
        ветви: ветви
      )
    )
    for сторона in стороны {
      try реестр.материализоватьИПроверитьКлон(
        поколение: поколение,
        сторона: сторона
      )
    }
    let общиеКаталоги = try общиеКаталогиКорневогоПаспорта(
      реестр.переносимыйПаспорт(поколение: поколение)
    )
    let задачи: [СторонаВетвевогоФорка: String] = [
      .левая: "задача.левая",
      .правая: "задача.правая",
    ]
    let среды: [СторонаВетвевогоФорка: String] = [
      .левая: "среда.левая",
      .правая: "среда.правая",
    ]
    let поддельнаяСреда = АвтономнаяПоддельнаяСредаЗадач(исходы: [
      .точный(
        идентификаторЗадачи: задачи[.левая] ?? "",
        идентификаторСреды: среды[.левая] ?? ""
      ),
      .точный(
        идентификаторЗадачи: задачи[.правая] ?? "",
        идентификаторСреды: среды[.правая] ?? ""
      ),
    ])
    var назначения: [СторонаВетвевогоФорка: СтруктурированноеРесурсноеНазначение] = [:]
    var допуски: [СторонаВетвевогоФорка: РешениеРесурсногоДопуска] = [:]
    var запросы: [СторонаВетвевогоФорка: ЗапросСозданияЗадачи] = [:]
    for сторона in стороны {
      guard let ветвь = ветви.first(where: { $0.сторона == сторона }),
        let ресурсныеПолномочия = полномочия[сторона],
        let общийКаталог = общиеКаталоги[сторона],
        let задача = задачи[сторона],
        let среда = среды[сторона]
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Не собрана официальная host/resource-привязка."
        )
      }
      let назначение = структурированноеНазначениеАвтономнойПриёмки(
        ветвь: ветвь,
        поколение: поколение,
        база: база,
        общийКаталог: общийКаталог,
        полномочия: ресурсныеПолномочия
      )
      let хэшНазначения = try реестр.зарегистрироватьРесурсноеНазначение(назначение)
      let допуск = try реестр.запроситьРесурсныйДопуск(
        назначение: назначение.идентификатор,
        попытка: "ресурсная-попытка.\(сторона.rawValue)",
        ожидаемыйХэшНазначения: хэшНазначения
      )
      guard допуск.состояние == .зарезервирована,
        допуск.хэшДопуска != nil
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Совместимая дочерняя ветвь не получила ресурсный допуск."
        )
      }
      try реестр.выполнитьЕдинственныйВызов(
        поколение: поколение,
        сторона: сторона,
        среда: поддельнаяСреда
      )
      let запрос = try поддельнаяСреда.запрос(сторона: сторона)
      try реестр.подтвердитьСеанс(
        поколение: поколение,
        сторона: сторона,
        переменнаяСеанса: задача,
        билет: СвидетельствоНеактивногоБилета(
          идентификаторЗадачи: задача,
          идентификаторСреды: среда,
          поколение: запрос.поколение,
          назначение: запрос.назначение,
          роль: запрос.роль,
          ребёнок: запрос.ребёнок,
          форк: запрос.форк,
          шаг: запрос.шаг,
          проект: запрос.проект,
          исходнаяВершина: запрос.исходнаяВершина,
          сторона: запрос.сторона,
          попытка: запрос.попытка,
          хэшКонверта: запрос.хэшКонверта,
          репозиторий: запрос.репозиторий,
          ссылка: запрос.рабочаяСсылка,
          рабочаяКопия: запрос.рабочаяКопия,
          активен: false,
          идентификаторРесурсногоНазначения: запрос.идентификаторРесурсногоНазначения,
          хэшРесурсногоНазначения: запрос.хэшРесурсногоНазначения,
          идентификаторРесурснойПопытки: запрос.идентификаторРесурснойПопытки,
          хэшРесурсногоДопуска: запрос.хэшРесурсногоДопуска
        )
      )
      назначения[сторона] = назначение
      допуски[сторона] = допуск
      запросы[сторона] = запрос
    }
    let хэшПредактивации = try реестр.сохранитьПредактивацию(поколение: поколение)
    let ожидаемыйХэшКвитанции = ресурсныйХэш(
      Data(
        "активация\u{0}поколение:\(поколение)\u{0}предактивация:\(хэшПредактивации)".utf8
      )
    )
    var допусковДоАктивации = 0
    for сторона in стороны {
      guard let задача = задачи[сторона] else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Потеряна задача предактивационного барьера."
        )
      }
      if try реестр.разрешитьВходВОчередь(
        поколение: поколение,
        сторона: сторона,
        идентификаторЗадачи: задача,
        хэшКвитанции: ожидаемыйХэшКвитанции
      ) {
        допусковДоАктивации += 1
      }
    }
    let активация = try реестр.активироватьПару(
      поколение: поколение,
      ожидаемыйХэш: хэшПредактивации
    )
    guard допусковДоАктивации == 0,
      активация.хэшКвитанции == ожидаемыйХэшКвитанции
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Предактивационный барьер не сохранил точную квитанцию."
      )
    }
    for сторона in стороны {
      guard let задача = задачи[сторона],
        let допуск = допуски[сторона],
        let хэшДопуска = допуск.хэшДопуска,
        try реестр.разрешитьВходВОчередь(
          поколение: поколение,
          сторона: сторона,
          идентификаторЗадачи: задача,
          хэшКвитанции: активация.хэшКвитанции
        )
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Активированная ветвь не получила exact очередь."
        )
      }
      _ = try реестр.изменитьСостояниеРесурснойСессии(
        попытка: допуск.попытка,
        хэшДопуска: хэшДопуска,
        новоеСостояние: .неактивныйРебёнок
      )
    }
    var официальныеДопуски: [СторонаВетвевогоФорка: ОфициальныйДопускДочернейЦепочки] = [:]
    for сторона in стороны {
      guard let назначение = назначения[сторона],
        let допуск = допуски[сторона],
        let запрос = запросы[сторона],
        let задача = задачи[сторона],
        let среда = среды[сторона],
        let рабочаяКопия = рабочиеКопии[сторона],
        let голыйРепозиторий = форки[сторона]
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Не восстановлена активированная ресурсная ветвь."
        )
      }
      let свидетельство = try свидетельствоЗахватаАвтономнойПриёмки(
        назначение: назначение,
        допуск: допуск,
        идентификаторЗадачи: задача,
        идентификаторСреды: среда
      )
      let активноеРешение = try реестр.захватитьДочернююРесурснуюСессию(
        свидетельство
      )
      guard активноеРешение.состояние == .активныйПисатель else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "До первого дочернего эффекта не захвачен активный писатель."
        )
      }
      официальныеДопуски[сторона] = ОфициальныйДопускДочернейЦепочки(
        сторона: сторона,
        назначение: назначение,
        допуск: допуск,
        запрос: запрос,
        идентификаторЗадачи: задача,
        идентификаторСреды: среда,
        свидетельствоЗахвата: свидетельство,
        активноеРешение: активноеРешение,
        рабочаяКопия: рабочаяКопия,
        голыйРепозиторий: голыйРепозиторий
      )
    }
    let доказательстваСреды: [String: СвидетельствоПоддельнойСреды] = try Dictionary(
      uniqueKeysWithValues: стороны.map { сторона in
        guard let описание = описанияПоСтороне[сторона],
          let допуск = официальныеДопуски[сторона],
          let хэшДопуска = допуск.допуск.хэшДопуска
        else {
          throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
            "Не восстановлена проекция официальной host/resource-привязки."
          )
        }
        return (
          описание.сторона,
          СвидетельствоПоддельнойСреды(
            идентификаторЗадачи: допуск.идентификаторЗадачи,
            идентификаторСреды: допуск.идентификаторСреды,
            хэшКвитанции: активация.хэшКвитанции,
            хэшПривязки: try хэшАвтономнойПриёмки([
              допуск.запрос.хэшКонверта,
              try допуск.назначение.каноническийХэш(),
              хэшДопуска,
              активация.хэшДоказательстваАктивации,
              допуск.идентификаторЗадачи,
              допуск.идентификаторСреды,
            ]),
            хэшКонверта: допуск.запрос.хэшКонверта
          )
        )
      }
    )

              ПроверкаКорневогоРевьюИИнтеграцииЦепочки
              .проверить(снимок)
            return прочитанное == свидетельство
              && повторныйОтчёт.решение == отчёт.решение
              && повторныйОтчёт.кодыНарушений == отчёт.кодыНарушений
          }

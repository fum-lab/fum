  fileprivate func создатьИВосстановитьПредложение(
    _ конверт: КонвертАвтономногоПредложенияИзФорка
  ) throws -> КонвертАвтономногоПредложенияИзФорка {
    let адрес = корень.appending(
      path: "состояние/предложения-слияния/\(конверт.идентификатор).json"
    )
    let проверятьСоздание = сбои.следуетПроверить(.созданиеПредложения)
    let намерениеСоздания = "создать_единственный_конверт_предложения"
    let наблюдениеСоздания = "конверт_создан:\(конверт.хэшКонверта)"
    if проверятьСоздание {
      try сбои.запланировать(.созданиеПредложения, намерение: намерениеСоздания)
    }
    try записатьАтомарно(try каноническиеДанныеАвтономнойПриёмки(конверт), по: адрес)
    if проверятьСоздание {
      do {
        try сбои.записатьЭффектИПотерятьОтвет(
          .созданиеПредложения,
          намерение: намерениеСоздания,
          наблюдение: наблюдениеСоздания
        )
      } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.намеренноеПрерывание {
        let новыйСеанс = try новыйСеансВосстановления()
        try новыйСеанс.сбои.восстановитьПослеПотериОтвета(
          .созданиеПредложения,
          намерение: намерениеСоздания,
          наблюдение: наблюдениеСоздания
        ) {
          let восстановленный = try JSONDecoder().decode(
            КонвертАвтономногоПредложенияИзФорка.self,
            from: Data(contentsOf: адрес)
          )
          return восстановленный == конверт
        }
      }
    }
    let проверятьЧтение = сбои.следуетПроверить(.авторитетноеЧтениеПредложения)
    let намерениеЧтения = "прочитать_и_проверить_конверт_предложения"
    if проверятьЧтение {
      try сбои.запланировать(
        .авторитетноеЧтениеПредложения,
        намерение: намерениеЧтения
      )
    }
    let прочитанный = try JSONDecoder().decode(
      КонвертАвтономногоПредложенияИзФорка.self,
      from: Data(contentsOf: адрес)
    )
    guard try конвертИмеетВерныйХэш(прочитанный) else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Авторитетное чтение предложения обнаружило подменённый конверт."
      )
    }
    if проверятьЧтение {
      let наблюдениеЧтения =
        "конверт_прочитан_и_хэш_проверен:\(прочитанный.хэшКонверта)"
      do {
        try сбои.записатьЭффектИПотерятьОтвет(
          .авторитетноеЧтениеПредложения,
          намерение: намерениеЧтения,
          наблюдение: наблюдениеЧтения
        )
      } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.намеренноеПрерывание {
        let новыйСеанс = try новыйСеансВосстановления()
        try новыйСеанс.сбои.восстановитьПослеПотериОтвета(
          .авторитетноеЧтениеПредложения,
          намерение: намерениеЧтения,
          наблюдение: наблюдениеЧтения
        ) {
          let повтор = try JSONDecoder().decode(
            КонвертАвтономногоПредложенияИзФорка.self,
            from: Data(contentsOf: адрес)
          )
          guard повтор == прочитанный else { return false }
          return try self.конвертИмеетВерныйХэш(повтор)
        }
      }
    }
    return прочитанный
  }

  fileprivate func конвертИмеетВерныйХэш(
    _ конверт: КонвертАвтономногоПредложенияИзФорка
  ) throws -> Bool {
    let нагрузка = НагрузкаКонвертаАвтономногоПредложения(

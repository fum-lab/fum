    }

    func терминальноеСвидетельство(
      назначение: СтруктурированноеРесурсноеНазначение,
      решение: РешениеРесурсногоДопуска
    ) throws -> СвидетельствоТерминализацииРесурсногоНазначения {
      guard let хэшДопуска = решение.хэшДопуска else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Терминализация не получила ресурсный допуск."
        )
      }
      return СвидетельствоТерминализацииРесурсногоНазначения(
        назначение: назначение.идентификатор,
        хэшНазначения: try назначение.каноническийХэш(),
        поколение: назначение.поколение,
        исходнаяВершина: назначение.исходнаяВершина,
        сторона: назначение.сторона,
        корневаяПопытка: назначение.корневаяПопытка,
        репозиторий: назначение.репозиторий,
        рабочаяСсылка: назначение.рабочаяСсылка,
        рабочаяКопия: назначение.рабочаяКопия,
        общийКаталог: назначение.общийКаталог,
        попытка: решение.попытка,
        хэшДопуска: хэшДопуска,
        идентификаторЗадачи: "",
        идентификаторСреды: "",
        конечнаяВершина: база,
        исход: .завершено
      )
    }

    let квитанция = try реестр.зафиксироватьТерминальныйИсход(
      терминальноеСвидетельство(
        назначение: левоеНазначение,
        решение: левоеРешение
      )
    )
    let правоеРешениеПосле = try реестр.восстановитьРесурсноеРешение(
      попытка: правоеРешениеДо.попытка
    )
    guard квитанция.допущенныеПопытки == [правоеРешениеДо.попытка],
      правоеРешениеПосле.состояние == .зарезервирована,
      правоеРешениеПосле.хэшДопуска != nil
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "FIFO не продвинул следующую конфликтную попытку после терминализации."
      )
    }
    _ = try реестр.зафиксироватьТерминальныйИсход(
      терминальноеСвидетельство(
        назначение: правоеНазначение,
        решение: правоеРешениеПосле
      )
    )
    return 1
  }

  fileprivate func заморозитьРезультатАвтономнойПриёмки(

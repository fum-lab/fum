      квитанция.сторона,
      описание.идентификаторРебёнка,
      описание.идентификаторРепозитория,
      описание.рабочаяСсылка,
      описание.идентификаторРабочейКопии,
      описание.роль,
      описание.маршрут,
      квитанция.идентификаторЗадачиСреды,
      квитанция.идентификаторСреды,
      квитанция.хэшКвитанцииСреды,
      квитанция.хэшПривязкиСреды,
      квитанция.хэшКонвертаСреды,
      квитанция.хэшПрофиляПолномочий,
      описание.идентификаторВладельца,
    ]
    guard квитанция.сторона == описание.сторона,
      квитанция.идентификаторРебёнка == описание.идентификаторРебёнка,
      квитанция.идентификаторРепозитория == описание.идентификаторРепозитория,
      квитанция.рабочаяСсылка == описание.рабочаяСсылка,
      квитанция.идентификаторРабочейКопии == описание.идентификаторРабочейКопии,
      квитанция.роль == описание.роль,
      квитанция.маршрут == описание.маршрут,
      квитанция.идентификаторВладельца == описание.идентификаторВладельца,
      квитанция.хэшКвитанции == (try хэшАвтономнойПриёмки(нагрузкаКвитанции))
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Ролевая цепочка не предъявила точную долговечную FIFO-квитанцию."
      )
    }
    guard рабочаяКопия == официальныйДопуск.рабочаяКопия,
      официальныйДопуск.назначение.поколение == квитанция.поколение,
      официальныйДопуск.назначение.репозиторий == описание.идентификаторРепозитория,
      официальныйДопуск.назначение.рабочаяСсылка == описание.рабочаяСсылка,
      официальныйДопуск.назначение.рабочаяКопия == описание.идентификаторРабочейКопии,
      try корневойРеестр.значение.захватитьДочернююРесурснуюСессию(
        официальныйДопуск.свидетельствоЗахвата
      ) == официальныйДопуск.активноеРешение,
      try текстКомандыКонтроляВерсий(
        ["symbolic-ref", "--quiet", "HEAD"],
        в: рабочаяКопия
      ) == описание.рабочаяСсылка
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Writer не восстановил свой exact host/resource-допуск."
      )
    }
    let поставщик = описание.роль == "поставщик_синтетического_навыка"
    try барьер.войти()
    defer { барьер.выйти() }

    if поставщик {
      let манифест =
        #"{"артефакт":"синтетический-навык","версия":1,"роль":"поставщик_синтетического_навыка","сеть":false}"#
      try записать(
        Data(манифест.utf8),
        по: рабочаяКопия.appending(path: "Манифесты/синтетический-навык.json")
      )
      _ = try выполнитьКомандуКонтроляВерсий(
        ["add", "--", "Манифесты/синтетический-навык.json"], в: рабочаяКопия)
      let намерениеСбояШага = "создать_первую_фиксацию_поставщика"
      try сбои.запланировать(.шаг, намерение: намерениеСбояШага)
      _ = try выполнитьКомандуКонтроляВерсий(
        ["commit", "--quiet", "-m", "Добавить манифест синтетического навыка"],
        в: рабочаяКопия,
        дата: "2001-01-01T00:00:01Z"
      )
      let вершинаПервогоШага = try текстКомандыКонтроляВерсий(
        ["rev-parse", "HEAD"], в: рабочаяКопия)
      let наблюдениеСбояШага =
        "фиксация_первого_шага_создана_публикация_ожидается:\(вершинаПервогоШага)"
      do {
        try сбои.записатьЭффектИПотерятьОтвет(
          .шаг,
          намерение: намерениеСбояШага,
          наблюдение: наблюдениеСбояШага
        )
      } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.намеренноеПрерывание {
        let новыйСеанс = try новыйСеансВосстановления()
        try новыйСеанс.сбои.восстановитьПослеПотериОтвета(
          .шаг,
          намерение: намерениеСбояШага,
          наблюдение: наблюдениеСбояШага
        ) {
          try self.текстКомандыКонтроляВерсий(["rev-parse", "HEAD"], в: рабочаяКопия)
            == вершинаПервогоШага
        }
      }
      try записать(
        Data(
          """
          # Синтетический навык

          Фикстура доказывает только перенос проверенного артефакта через автономный контур.
          """.utf8
        ),
        по: рабочаяКопия.appending(path: "Навыки/синтетический-навык/SKILL.md")
      )
      _ = try выполнитьКомандуКонтроляВерсий(
        ["add", "--", "Навыки/синтетический-навык/SKILL.md"], в: рабочаяКопия)
      _ = try выполнитьКомандуКонтроляВерсий(
        ["commit", "--quiet", "-m", "Добавить синтетический навык"],
        в: рабочаяКопия,
        дата: "2001-01-01T00:00:02Z"
      )
    } else {
      try записать(
        Data(
          "# Критерии синтетического навыка\n\nПроверить манифест, границу эффектов и происхождение.\n"
            .utf8
        ),
        по: рабочаяКопия.appending(path: "Ревью/критерии-синтетического-навыка.md")
      )
      _ = try выполнитьКомандуКонтроляВерсий(
        ["add", "--", "Ревью/критерии-синтетического-навыка.md"], в: рабочаяКопия)
      _ = try выполнитьКомандуКонтроляВерсий(
        ["commit", "--quiet", "-m", "Добавить ролевые критерии проверки"],
        в: рабочаяКопия,
        дата: "2001-01-01T00:00:01Z"
      )
      try записать(
        Data(
          "# Требуется доработка\n\nДиагностический кандидат намеренно не содержит исполняемый артефакт.\n"
            .utf8
        ),
        по: рабочаяКопия.appending(path: "Диагностика/требуется-доработка.md")
      )
      _ = try выполнитьКомандуКонтроляВерсий(
        ["add", "--", "Диагностика/требуется-доработка.md"], в: рабочаяКопия)
      _ = try выполнитьКомандуКонтроляВерсий(
        ["commit", "--quiet", "-m", "Зафиксировать точную диагностику доработки"],
        в: рабочаяКопия,
        дата: "2001-01-01T00:00:02Z"
      )
    }
    let вершина = try текстКомандыКонтроляВерсий(["rev-parse", "HEAD"], в: рабочаяКопия)
    let коммиты = try текстКомандыКонтроляВерсий(
      ["rev-list", "--reverse", "\(база)..\(вершина)"],
      в: рабочаяКопия
    )
    .split(separator: "\n").map(String.init)
    _ = try выполнитьКомандуКонтроляВерсий(
      ["push", официальныйДопуск.голыйРепозиторий.path, "HEAD:\(описание.рабочаяСсылка)"],
      в: рабочаяКопия
    )
    guard
      try текстКомандыКонтроляВерсий(
        ["rev-parse", описание.рабочаяСсылка],
        в: официальныйДопуск.голыйРепозиторий
      ) == вершина,
      try текстКомандыКонтроляВерсий(
        ["status", "--porcelain=v1", "--untracked-files=all"],
        в: рабочаяКопия
      ).isEmpty
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Ролевая цепочка не опубликовала exact ref или оставила незаписанные файлы."
      )
    }
    let терминальнаяКвитанция = try корневойРеестр.значение
      .зафиксироватьТерминальныйИсход(
        терминальноеСвидетельствоАвтономнойПриёмки(
          допуск: официальныйДопуск,
          конечнаяВершина: вершина
        )
      )
    guard терминальнаяКвитанция.попытка == официальныйДопуск.допуск.попытка,
      try корневойРеестр.значение.восстановитьРесурсноеРешение(
        попытка: официальныйДопуск.допуск.попытка
      ).состояние == .завершена
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Ресурсное назначение не терминализировано после публикации."
      )
    }
    return СвидетельствоДочернейРолевойЦепочки(
      идентификаторФорка: описание.идентификаторРебёнка,
      идентификаторРепозитория: описание.идентификаторРепозитория,
      рабочаяСсылка: описание.рабочаяСсылка,
      идентификаторРабочейКопии: описание.идентификаторРабочейКопии,
      роль: описание.роль,
      маршрут: описание.маршрут,
      хэшПрофиляПолномочий: квитанция.хэшПрофиляПолномочий,
      база: база,
      коммиты: коммиты,
      вершина: вершина
    )
  }


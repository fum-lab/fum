      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Корневой паспорт не содержит материализованные ветви."
      )
    }
    var результат: [СторонаВетвевогоФорка: String] = [:]
    for ветвь in ветви {
      guard let сыраяСторона = ветвь["сторона"] as? String,
        let сторона = СторонаВетвевогоФорка(rawValue: сыраяСторона),
        let каталог = ветвь["общий_каталог_гит"] as? String,
        !каталог.isEmpty,
        результат[сторона] == nil
      else {
        throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
          "Корневой паспорт содержит неоднозначную ветвь."
        )
      }
      результат[сторона] = каталог
    }
    guard Set(результат.keys) == Set([.левая, .правая]) else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Корневой паспорт не сохранил точную пару ветвей."
      )
    }
    return результат
  }


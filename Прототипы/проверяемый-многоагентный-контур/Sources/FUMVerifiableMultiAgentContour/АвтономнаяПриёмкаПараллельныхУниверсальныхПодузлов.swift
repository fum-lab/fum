          )
        } catch ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.намеренноеПрерывание {
          let новыйСеанс = try новыйСеансВосстановления()
          let прочитанное = try JSONDecoder().decode(
            СвидетельствоАвтономногоРевью.self,
            from: Data(contentsOf: адрес)
          )
          try новыйСеанс.сбои.восстановитьПослеПотериОтвета(
            .ревью,
            намерение: намерениеСбояРевью,
            наблюдение: наблюдениеСбояРевью
          ) {

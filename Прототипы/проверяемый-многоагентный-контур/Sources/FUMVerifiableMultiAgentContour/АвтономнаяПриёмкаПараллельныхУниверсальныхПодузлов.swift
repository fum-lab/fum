      намерение: намерение,
      наблюдение: nil,
      фаза: .намерениеСохранено
    )
    try FileManager.default.createDirectory(
      at: адрес.deletingLastPathComponent(),
      withIntermediateDirectories: true
    )
    try каноническиеДанныеАвтономнойПриёмки(снимок).write(to: адрес, options: .atomic)
  }

  func записатьЭффектИПотерятьОтвет(
    _ точка: ТочкаСбояАвтономнойПриёмки,
    намерение: String,
    наблюдение: String
  ) throws -> Never {
    var снимок = try прочитать(точка)
    guard снимок.поколение == "поколение.параллельные-универсальные-подузлы.1",
      снимок.точка == точка.rawValue,
      снимок.намерение == намерение,
      снимок.фаза == .намерениеСохранено,
      снимок.наблюдение == nil
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Точка сбоя не содержит exact ожидающее намерение: \(точка.rawValue)."
      )
    }
    снимок.наблюдение = наблюдение
    снимок.фаза = .эффектНаблюдён
    try каноническиеДанныеАвтономнойПриёмки(снимок).write(
      to: адресТочки(точка),
      options: .atomic
    )
    throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.намеренноеПрерывание
  }

  func восстановитьПослеПотериОтвета(
    _ точка: ТочкаСбояАвтономнойПриёмки,
    намерение: String,
    наблюдение: String,
    авторитетнаяПроверка: () throws -> Bool
  ) throws {
    var снимок = try прочитать(точка)
    guard снимок.поколение == "поколение.параллельные-универсальные-подузлы.1",
      снимок.точка == точка.rawValue,
      снимок.намерение == намерение,
      снимок.наблюдение == наблюдение,
      снимок.фаза == .эффектНаблюдён || снимок.фаза == .восстановлено,
      try авторитетнаяПроверка()
    else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Точка сбоя не восстановила авторитетный эффект: \(точка.rawValue)."
      )
    }
    if снимок.фаза != .восстановлено {
      снимок.фаза = .восстановлено
      try каноническиеДанныеАвтономнойПриёмки(снимок).write(
        to: адресТочки(точка),
        options: .atomic
      )
    }
  }

  var точки: [String] {
    ТочкаСбояАвтономнойПриёмки.allCases.compactMap { точка in
      guard
        let снимок = try? JSONDecoder().decode(
          СостояниеТочкиСбояАвтономнойПриёмки.self,
          from: Data(contentsOf: адресТочки(точка))
        ), снимок.фаза == .восстановлено
      else { return nil }
      return точка.rawValue
    }.sorted()
  }

  func всеФайлыУчтены() throws -> Bool {
    try ТочкаСбояАвтономнойПриёмки.allCases.allSatisfy { точка in
      let каталог = адресТочки(точка).deletingLastPathComponent()
      let содержимое = try FileManager.default.contentsOfDirectory(
        at: каталог,
        includingPropertiesForKeys: nil
      ).map(\.lastPathComponent).sorted()
      return содержимое == ["состояние.json"]
    }
  }

  func состояние(_ точка: ТочкаСбояАвтономнойПриёмки) throws -> String {
    guard let наблюдение = try прочитать(точка).наблюдение else {
      throw ОшибкаАвтономнойПриёмкиПараллельныхПодузлов.нарушение(
        "Точка сбоя не содержит авторитетного наблюдения: \(точка.rawValue)."
      )
    }
    return наблюдение
  }

  private func прочитать(
    _ точка: ТочкаСбояАвтономнойПриёмки
  ) throws -> СостояниеТочкиСбояАвтономнойПриёмки {
    try JSONDecoder().decode(
      СостояниеТочкиСбояАвтономнойПриёмки.self,
      from: Data(contentsOf: адресТочки(точка))
    )
  }

  private func адресТочки(_ точка: ТочкаСбояАвтономнойПриёмки) -> URL {
    корень.appending(path: "\(точка.rawValue)/состояние.json")
  }
}


public enum АвтономнаяПриёмкаПараллельныхУниверсальныхПодузлов {
  public static func выполнить() throws
    -> ОтчётАвтономнойПриёмкиПараллельныхУниверсальныхПодузлов
  {
    let первый = try СтендАвтономнойПриёмкиПараллельныхПодузлов().выполнить()
    let повторный = try СтендАвтономнойПриёмкиПараллельныхПодузлов().выполнить()

    let идентичностиДочернихЦепочек = Set(
      первый.дочерниеЦепочки.flatMap {
        [$0.идентификаторФорка, $0.идентификаторРепозитория, $0.идентификаторРабочейКопии]
      })
    let проверяющие = Set(первый.ревью.map(\.идентификаторПроверяющего))
    let ревьюТочноСвязаны =
      первый.ревью.count == 2
      && проверяющие.count == 2
      && проверяющие.isDisjoint(with: идентичностиДочернихЦепочек)
      && Set(первый.ревью.map(\.хэшКонверта))
        == Set(первый.конвертыПредложений.map(\.хэшКонверта))
      && первый.ревью.allSatisfy { свидетельство in
        guard
          let конверт = первый.конвертыПредложений.first(where: {
            $0.хэшКонверта == свидетельство.хэшКонверта
          })
        else { return false }
        return свидетельство.база == конверт.база
          && свидетельство.вершина == конверт.вершина
      }
    let конвертыТочноСвязаны =
      try первый.конвертыПредложений.count == 2
      && первый.конвертыПредложений.allSatisfy { конверт in
        guard let цепочка = первый.дочерниеЦепочки.first(where: { $0.роль == конверт.роль }),
          let прочитанныйХэш = первый.хэшиПрочитанныхАртефактов[конверт.идентификатор]
        else { return false }
        let нагрузка = НагрузкаКонвертаАвтономногоПредложения(
          идентификатор: конверт.идентификатор,
          база: конверт.база,
          вершина: конверт.вершина,
          полныйДиапазон: конверт.полныйДиапазон,
          роль: конверт.роль,
          хэшМанифестаФикстуры: конверт.хэшМанифестаФикстуры
        )
        let ожидаемыйХэшКонверта = try хэшАвтономнойПриёмки(нагрузка)
        return конверт.база == цепочка.база
          && конверт.вершина == цепочка.вершина
          && конверт.полныйДиапазон == цепочка.коммиты
          && конверт.роль == цепочка.роль
          && конверт.хэшМанифестаФикстуры == прочитанныйХэш
          && конверт.хэшКонверта == ожидаемыйХэшКонверта
      }

    let проверки = [
      проверка(
        "две-двухшаговые-ролевые-цепочки",
        первый.дочерниеЦепочки.count == 2
          && первый.дочерниеЦепочки.allSatisfy { $0.коммиты.count == 2 }
          && Set(первый.дочерниеЦепочки.map(\.база)).count == 1
          && Set(первый.дочерниеЦепочки.map(\.идентификаторФорка)).count == 2
          && Set(первый.дочерниеЦепочки.map(\.идентификаторРепозитория)).count == 2
          && Set(первый.дочерниеЦепочки.map(\.рабочаяСсылка)).count == 2
          && Set(первый.дочерниеЦепочки.map(\.идентификаторРабочейКопии)).count == 2
          && первый.родительскаяРабочаяКопияНеизменна,
        "Два универсальных исполнителя прошли по две фиксации в разных ответвлениях, клонах и полных ссылках от одной базы; родительская рабочая копия не изменилась."
      ),
      проверка(
        "активация-и-единственность-владельцев",
        первый.допусковДоАктивации == 0
          && !первый.частичныйЗапускАктивировалПоколение
          && !первый.неизвестныйЗапускАктивировалПоколение
          && первый.максимумВладельцевОдногоРебёнка == 1
          && !первый.ожидающееПродолжениеУчтеноКакВторойВладелец
          && первый.дубликатДочернегоВладельцаОтклонён,
        "Предактивационный барьер закрыт; только точная пара среды получает очередь, а ожидающее продолжение не становится владельцем."
      ),
      проверка(
        "освобождение-и-восстановление-модератора",
        первый.родительскаяСессияОсвобождена
          && первый.модераторВосстановленВНовомСеансе
          && !первый.модераторИзменилДочерниеСсылки,
        "Долговечный паспорт восстановлен новым сеансом того же ответвления после освобождения родителя; дочерние ссылки остались заморожены."
      ),
      проверка(
        "роли-не-расширяют-полномочия",
        Set(первый.дочерниеЦепочки.map(\.роль)).count == 2
          && Set(первый.дочерниеЦепочки.map(\.маршрут)).count == 2
          && Set(первый.дочерниеЦепочки.map(\.хэшПрофиляПолномочий)).count == 1,
        "Роли выбрали разные конечные цепочки при одном профиле полномочий."
      ),
      проверка(
        "совместимость-перекрывается-конфликт-сериализуется",
        первый.максимумСовместимыхЗапусков == 2
          && первый.максимумКонфликтующихЗапусков == 1,
        "Совместимые назначения встретились на общем барьере, а две попытки одной цели исполнялись последовательно."
      ),
      проверка(
        "раздельное-ревью-и-сравнительная-интеграция",
        Set(первый.ревью.map(\.исход)) == Set([.принято, .наДоработку])
          && первый.ревью.allSatisfy(\.точнаяВершина)
          && ревьюТочноСвязаны
          && Set(первый.проверенныеОтрицательныеОгражденияРевью)
            == Set([
              "база_сдвинута",
              "вершина_сдвинута",
              "критерии_сдвинуты",
              "проверяющий_не_независим",
              "запрос_слияния_не_действителен",
            ])
          && первый.интегрированТолькоПринятыйДиапазон,
        "Два независимых проверяющих закрепили противоположные решения за точными вершинами; сравнительная замена приняла только разрешённый диапазон."
      ),
      проверка(
        "точный-конверт-предложения-и-транспорт-навыка",
        конвертыТочноСвязаны
          && первый.движениеГраницыАннулировалоРевью
          && первый.принятыйАртефактПрочитанНовымАгентом,
        "Локальные конверты закрепили основу, вершину, диапазон, роль и манифест; движение границы сняло принятие, а новый клон прочитал принятый синтетический навык."
      ),
      проверка(
        "синхронизация-ответвления-и-сравнительная-замена-сборки",
        первый.сагаСинхронизации.состояния == [
          СостояниеПереходаКорневойИнтеграцииЦепочки
            .принятоВЯдреСинхронизацияРебёнкаОжидается.rawValue,
          СостояниеПереходаКорневойИнтеграцииЦепочки
            .согласованиеСсылокСборкиОжидается.rawValue,
          СостояниеПереходаКорневойИнтеграцииЦепочки.завершено.rawValue,
        ]
          && первый.сагаСинхронизации.зеркальнаяВершинаЯдра
            == первый.сагаСинхронизации.принятаяВершинаЯдра
          && первый.сагаСинхронизации.дочерняяВершина
            != первый.сагаСинхронизации.вершинаПредложения
          && первый.сагаСинхронизации.дочерняяВершинаПотомокЯдра
          && первый.сагаСинхронизации.ссылкаПодмодуляЯдра
            == первый.сагаСинхронизации.принятаяВершинаЯдра
          && первый.сагаСинхронизации.ссылкаПодмодуляРебёнка
            == первый.сагаСинхронизации.дочерняяВершина
          && первый.сагаСинхронизации.числоСравнительныхЗаменСборки == 1,
        "После принятия ядра ответвление синхронизировало зеркальный `master`, создало дочернюю фиксацию и одной сравнительной заменой сборочной ссылки закрепило две ссылки подмодулей."
      ),
      проверка(
        "сбои-возобновляются-без-промежуточного-мусора",
        Set(первый.проверенныеТочкиСбоев)
          == Set(ТочкаСбояАвтономнойПриёмки.allCases.map(\.rawValue))
          && первый.промежуточныеФайлыУчтены
          && первый.точныйПовторПослеУспешнойСравнительнойЗамены
          && первый.возобновляемоеСостояниеПослеСравнительнойЗамены
            == "цель_продвинута_следующий_переход_ожидается:"
            + первый.сагаСинхронизации.принятаяВершинаЯдра,
        "Восемь границ имеют долговечное состояние; победа сравнительной замены распознаётся точным повтором без отката и неучтённых файлов."
      ),
      проверка(
        "повтор-и-свежие-клоны",
        первый.хэшПаспорта == повторный.хэшПаспорта
          && первый.хэшДиагностики == повторный.хэшДиагностики
          && первый.итоговыеДеревья == повторный.итоговыеДеревья
          && первый.свежиеКлоныВосстановилиОтсоединённыеСнимки
          && первый.свежиеКлоныВосстановилиСобственныеОчереди
          && повторный.свежиеКлоныВосстановилиОтсоединённыеСнимки
          && повторный.свежиеКлоныВосстановилиСобственныеОчереди,
        "Два полных прогона эквивалентны по каноническим хэшам и деревьям; свежая композиция восстановила отсоединённые снимки и отдельные очереди."
      ),
      проверка(
        "автономная-доказательная-граница",
        первый.запрещённыеЭффекты.isEmpty && повторный.запрещённыеЭффекты.isEmpty,
        "Реестр эффектов видел только локальные операции Git и файловой системы без сети, модели, секретов, внешней публикации и реальной среды задач."
      ),
    ]
    let граница =
      "Локальный синтетический транспорт без сети, модели, секретов, внешней публикации и реальных задач среды; полезность навыка и реализация fum-optimizator не заявлены."
    return ОтчётАвтономнойПриёмкиПараллельныхУниверсальныхПодузлов(
      решение: проверки.allSatisfy(\.пройдена) ? .принято : .отклонено,
      проверки: проверки,
      дочерниеЦепочки: первый.дочерниеЦепочки,
      родительскаяРабочаяКопияНеизменна: первый.родительскаяРабочаяКопияНеизменна,
      допусковДоАктивации: первый.допусковДоАктивации,
      частичныйЗапускАктивировалПоколение: первый.частичныйЗапускАктивировалПоколение,
      неизвестныйЗапускАктивировалПоколение: первый.неизвестныйЗапускАктивировалПоколение,
      максимумВладельцевОдногоРебёнка: первый.максимумВладельцевОдногоРебёнка,
      ожидающееПродолжениеУчтеноКакВторойВладелец:
        первый.ожидающееПродолжениеУчтеноКакВторойВладелец,
      дубликатДочернегоВладельцаОтклонён:
        первый.дубликатДочернегоВладельцаОтклонён,
      родительскаяСессияОсвобождена: первый.родительскаяСессияОсвобождена,
      модераторВосстановленВНовомСеансе: первый.модераторВосстановленВНовомСеансе,
      модераторИзменилДочерниеСсылки: первый.модераторИзменилДочерниеСсылки,
      максимумСовместимыхЗапусков: первый.максимумСовместимыхЗапусков,
      максимумКонфликтующихЗапусков: первый.максимумКонфликтующихЗапусков,
      ревью: первый.ревью,
      проверенныеОтрицательныеОгражденияРевью:
        первый.проверенныеОтрицательныеОгражденияРевью,
      конвертыПредложений: первый.конвертыПредложений,
      движениеГраницыАннулировалоРевью: первый.движениеГраницыАннулировалоРевью,
      сагаСинхронизации: первый.сагаСинхронизации,
      принятыйАртефактПрочитанНовымАгентом: первый.принятыйАртефактПрочитанНовымАгентом,
      проверенныеТочкиСбоев: первый.проверенныеТочкиСбоев,
      промежуточныеФайлыУчтены: первый.промежуточныеФайлыУчтены,
      точныйПовторПослеУспешнойСравнительнойЗамены: первый
        .точныйПовторПослеУспешнойСравнительнойЗамены,
      состояниеВозобновленияПослеСравнительнойЗамены:
        первый.возобновляемоеСостояниеПослеСравнительнойЗамены,
      первыйХэшПаспорта: первый.хэшПаспорта,
      повторныйХэшПаспорта: повторный.хэшПаспорта,
      первыйХэшДиагностики: первый.хэшДиагностики,
      повторныйХэшДиагностики: повторный.хэшДиагностики,
      первыеИтоговыеДеревья: первый.итоговыеДеревья,
      повторныеИтоговыеДеревья: повторный.итоговыеДеревья,
      свежиеКлоныВосстановилиОтсоединённыеСнимки:
        первый.свежиеКлоныВосстановилиОтсоединённыеСнимки,
      свежиеКлоныВосстановилиСобственныеОчереди:
        первый.свежиеКлоныВосстановилиСобственныеОчереди,
      запрещённыеЭффекты: Array(Set(первый.запрещённыеЭффекты + повторный.запрещённыеЭффекты))
        .sorted(),
      границаДоказательства: граница
    )
  }

  private static func проверка(
    _ идентификатор: String,
    _ пройдена: Bool,
    _ свидетельство: String
  ) -> ПроверкаСквознойПриёмки {
    ПроверкаСквознойПриёмки(
      идентификатор: идентификатор,
      пройдена: пройдена,
      свидетельство: свидетельство
    )
  }
}


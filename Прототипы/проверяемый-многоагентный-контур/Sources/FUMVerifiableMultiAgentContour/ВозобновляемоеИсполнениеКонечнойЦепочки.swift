struct РезультатЛокальногоПроцесса: Sendable {
  let аргументы: [String]
  let код: Int32
  let данные: Data
  let текст: String
}

struct ОтветСтруктурированныхДанныхИнструмента {
  let код: Int32
  let данные: Data
  let объект: [String: Any]
}

enum ИнструментыВозобновляемойЦепочки {
  private static let путьОчереди =
    "Инструменты/fum-ocheredj-zadach-git-vetki/scripts/ocheredj-zadach-git-vetki.py"
  private static let путьСелектора =
    "Инструменты/fum-sleduyusjhij-shag-vetki/scripts/branch-next-step.py"
  private static let кодЗагрузкиОчереди =
    """
    import os,subprocess,sys
    p=sys.argv[2]
    r=sys.argv[1]
    e={k:v for k,v in os.environ.items() if not k.upper().startswith('GIT_')}
    e['GIT_NO_REPLACE_OBJECTS']='1'
    e['GIT_OPTIONAL_LOCKS']='0'
    b=subprocess.check_output(['git','--no-replace-objects','-C',r,'show','HEAD:'+p],env=e,timeout=30)
    sys.argv=[p,*sys.argv[3:],'--repo-root',r]
    exec(compile(b,p,'exec'))
    """

  static func очередь(
    корень: URL,
    аргументы: [String]
  ) throws -> ОтветСтруктурированныхДанныхИнструмента {
    let запуск = try запуститьПроцесс(
      исполняемыйФайл: try найтиПитон3(),
      аргументы: ["-I", "-c", кодЗагрузкиОчереди, корень.path, путьОчереди] + аргументы,
      корень: корень
    )
    guard !запуск.данные.isEmpty else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.командаНеВыполнена(
        запуск.аргументы, запуск.код, запуск.текст
      )
    }
    return ОтветСтруктурированныхДанныхИнструмента(
      код: запуск.код,
      данные: запуск.данные,
      объект: try КодированиеВозобновляемойЦепочки.объект(запуск.данные)
    )
  }

  static func селектор(корень: URL) throws -> ОтветСтруктурированныхДанныхИнструмента {
    let запуск = try запуститьПроцесс(
      исполняемыйФайл: try найтиПитон3(),
      аргументы: [
        корень.appendingPathComponent(путьСелектора).path,
        "show", "--repo-root", корень.path, "--json",
      ],
      корень: корень
    )
    guard !запуск.данные.isEmpty else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.командаНеВыполнена(
        запуск.аргументы, запуск.код, запуск.текст
      )
    }
    return ОтветСтруктурированныхДанныхИнструмента(
      код: запуск.код,
      данные: запуск.данные,
      объект: try КодированиеВозобновляемойЦепочки.объект(запуск.данные)
    )
  }

  static func текстГит(_ аргументы: [String], корень: URL) throws -> String {
    String(decoding: try данныеГит(аргументы, корень: корень), as: UTF8.self)
      .trimmingCharacters(in: .whitespacesAndNewlines)
  }

  static func данныеГит(_ аргументы: [String], корень: URL) throws -> Data {
    try WritingSubnodeGit().data(аргументы, at: корень)
  }

  static func записатьСсылкуСтруктурированныхДанных(
    _ объект: [String: Any],
    ссылка: String,
    прежнийОбъект: String?,
    корень: URL
  ) throws -> String {
    let данные = try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(объект)
    let новыйОбъект = try текстГит(
      ["hash-object", "-w", "--stdin"],
      корень: корень,
      ввод: данные
    )
    var аргументы = ["update-ref", ссылка, новыйОбъект]
    аргументы.append(прежнийОбъект ?? "")
    _ = try текстГит(аргументы, корень: корень)
    return новыйОбъект
  }

  static func прочитатьСсылкуСтруктурированныхДанных(
    _ ссылка: String,
    корень: URL
  ) throws -> ([String: Any], String)? {
    let список = try текстГит(
      ["for-each-ref", "--format=%(objectname)", ссылка],
      корень: корень
    )
    guard !список.isEmpty else { return nil }
    let строки = список.split(separator: "\n")
    guard строки.count == 1 else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Служебная ссылка неоднозначна."
      )
    }
    let идентификаторОбъекта = String(строки[0])
    let данные = try данныеГит(["cat-file", "blob", идентификаторОбъекта], корень: корень)
    return (try КодированиеВозобновляемойЦепочки.объект(данные), идентификаторОбъекта)
  }

  static func запуститьПроцесс(
    исполняемыйФайл: URL,
    аргументы: [String],
    корень: URL
  ) throws -> РезультатЛокальногоПроцесса {
    let процесс = Process()
    процесс.executableURL = исполняемыйФайл
    процесс.arguments = аргументы
    процесс.currentDirectoryURL = корень
    var окружение = ProcessInfo.processInfo.environment.filter {
      !$0.key.uppercased().hasPrefix("GIT_")
    }
    окружение["GIT_CONFIG_NOSYSTEM"] = "1"
    окружение["GIT_CONFIG_GLOBAL"] = WritingSubnodeSystemRuntime.nullDevicePath
    окружение["GIT_OPTIONAL_LOCKS"] = "0"
    окружение["GIT_TERMINAL_PROMPT"] = "0"
    окружение["LC_ALL"] = "C"
    процесс.environment = окружение
    let вывод = Pipe()
    let ошибки = Pipe()
    процесс.standardOutput = вывод
    процесс.standardError = ошибки
    try процесс.run()
    try вывод.fileHandleForWriting.close()
    try ошибки.fileHandleForWriting.close()
    let данные = вывод.fileHandleForReading.readDataToEndOfFile()
    let данныеОшибок = ошибки.fileHandleForReading.readDataToEndOfFile()
    процесс.waitUntilExit()
    return РезультатЛокальногоПроцесса(
      аргументы: аргументы,
      код: процесс.terminationStatus,
      данные: данные,
      текст: String(decoding: данные + данныеОшибок, as: UTF8.self)
    )
  }

  static func текстГит(
    _ аргументы: [String],
    корень: URL,
    ввод: Data
  ) throws -> String {
    try WritingSubnodeGit().text(аргументы, at: корень, input: ввод)
  }

  private static func найтиПитон3() throws -> URL {
    let пути = ProcessInfo.processInfo.environment["PATH"]?.split(separator: ":") ?? []
    for путь in пути {
      let кандидат = URL(fileURLWithPath: String(путь)).appendingPathComponent("python3")
      if FileManager.default.isExecutableFile(atPath: кандидат.path) { return кандидат }
    }
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
      "python3 отсутствует в PATH."
    )
  }
}

enum КодированиеВозобновляемойЦепочки {
  static func кодировать<T: Encodable>(_ значение: T) throws -> Data {
    let кодировщик = JSONEncoder()
    кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
    return try кодировщик.encode(значение)
  }

  static func каноническиеДанныеОбъекта(_ объект: [String: Any]) throws -> Data {
    guard JSONSerialization.isValidJSONObject(объект) else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неверныйОтвет(
        "Объект не сериализуется в JSON."
      )
    }
    return try JSONSerialization.data(
      withJSONObject: объект,
      options: [.sortedKeys, .withoutEscapingSlashes]
    )
  }

  static func объект(_ данные: Data) throws -> [String: Any] {
    guard
      let объект = try JSONSerialization.jsonObject(with: данные) as? [String: Any]
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неверныйОтвет(
        "Ожидался корневой JSON-объект."
      )
    }
    return объект
  }
}

func строка(_ объект: [String: Any], _ поле: String) throws -> String {
  guard let значение = объект[поле] as? String, !значение.isEmpty else {
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неверныйОтвет(
      "Поле \(поле) отсутствует или не является строкой."
    )
  }
  return значение
}

func необязательнаяСтрока(_ объект: [String: Any], _ поле: String) throws -> String? {
  guard let значение = объект[поле] else { return nil }
  if значение is NSNull { return nil }
  guard let строка = значение as? String, !строка.isEmpty else {
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неверныйОтвет(
      "Поле \(поле) имеет неверный строковый тип."
    )
  }
  return строка
}

func целое(_ объект: [String: Any], _ поле: String) throws -> Int {
  guard let число = объект[поле] as? NSNumber,
    CFGetTypeID(число) != CFBooleanGetTypeID()
  else {
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неверныйОтвет(
      "Поле \(поле) отсутствует или не является целым."
    )
  }
  return число.intValue
}

  private func проверитьОстатокБюджета(
    для план: ПланФикстурыВозобновляемойЦепочки
  ) throws {
    let пути = try ИнструментыВозобновляемойЦепочки.текстГит(
      [
        "-c", "core.quotePath=false",
        "ls-tree", "-r", "--name-only", "HEAD", "--", "Паспорта/шагов",
      ],
      корень: кореньЧекаута
    ).split(separator: "\n").map(String.init)
    var использованоТокенов = 0
    var использованоСекунд = 0
    var использованоФайлов = 0
    for путь in пути where !путь.isEmpty {
      let данные = try ИнструментыВозобновляемойЦепочки.данныеГит(
        ["show", "HEAD:\(путь)"], корень: кореньЧекаута
      )
      let паспорт = try КодированиеВозобновляемойЦепочки.объект(данные)
      использованоТокенов += try целое(паспорт, "токены")
      использованоСекунд += try целое(паспорт, "секунды")
      использованоФайлов += try целое(паспорт, "изменённые_файлы")
      if план.идентификаторКарточки == "FUM-STEP-9002" {
        guard try строка(паспорт, "идентификатор_карточки") == "FUM-STEP-9001",
          try строка(паспорт, "хэш_карточки")
            == СодержимоеФикстурыВозобновляемойЦепочки.хэш(
              Data(СодержимоеФикстурыВозобновляемойЦепочки.перваяКарточка.utf8)
            )
        else {
          throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
            "Паспорт предшественника не связан с исходной карточкой."
          )
        }
      }
    }
    let пределы = try прочитатьПределыБюджета()
    guard использованоТокенов + план.токены <= пределы.токены,
      использованоСекунд + план.секунды <= пределы.секунды,
      использованоФайлов + план.изменённыеФайлы <= пределы.файлы
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Остаток бюджета не разрешает выбранный шаг."
      )
    }
    if план.идентификаторКарточки == "FUM-STEP-9002", пути.count != 1 {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Второй шаг не восстановил единственный паспорт предшественника из HEAD."
      )
    }
  }

  private func прочитатьПределыБюджета() throws -> (
    токены: Int, секунды: Int, файлы: Int
  ) {
    let статус = try ИнструментыВозобновляемойЦепочки.очередь(
      корень: кореньЧекаута,
      аргументы: ["status", "--json"]
    ).объект
    let рабочаяКопия = try строка(статус, "worktree_id")
    let рабочаяСсылка = try строка(статус, "branch_ref")
    let хэшСсылки = SHA256.hash(data: Data(рабочаяСсылка.utf8)).map {
      String(format: "%02x", $0)
    }.joined()
    let ссылка = "refs/fum/назначения-конечных-цепочек/\(рабочаяКопия)/\(хэшСсылки)"
    guard
      let (назначение, _) =
        try ИнструментыВозобновляемойЦепочки.прочитатьСсылкуСтруктурированныхДанных(
          ссылка, корень: кореньЧекаута
        )
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Не найдено закреплённое назначение для бюджета."
      )
    }
    guard let границы = назначение["границы"] as? [String: Any],
      let бюджеты = границы["бюджеты"] as? [String: Any]
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неверныйОтвет(
        "Назначение не содержит границы бюджета."
      )
    }
    return (
      try целое(бюджеты, "токены"),
      try целое(бюджеты, "секунды"),
      try целое(бюджеты, "изменённые_файлы")
    )
  }

  private func подготовитьИзменения(
    _ план: ПланФикстурыВозобновляемойЦепочки,
    допуск: ДопускВозобновляемойЦепочки,
    режим: РежимСессииВозобновляемойЦепочки
  ) throws {
    for запись in план.записи {
      try WritingSubnodePersistence.materialize(запись, cloneURL: кореньЧекаута)
    }
    for путь in план.удаления {
      let адрес = кореньЧекаута.appendingPathComponent(путь)
      if FileManager.default.fileExists(atPath: адрес.path) {
        try FileManager.default.removeItem(at: адрес)
      } else {
        _ = try ИнструментыВозобновляемойЦепочки.данныеГит(
          ["show", "HEAD:\(путь)"], корень: кореньЧекаута
        )
      }
    }
    var дополнительныеОбъявленныеПути: [String] = []
    if режим == .незаявленныйПуть {
      try WritingSubnodePersistence.materialize(
        WritingSubnodeWrite(
          path: "Результаты/цепочка/незаявленный-путь.txt",
          contents: Data("незаявленное изменение\n".utf8)
        ),
        cloneURL: кореньЧекаута
      )
    }
    if режим == .заявленныйПутьВнеОбласти {
      let путь = "ВнеОбласти/заявленный-путь.txt"
      try WritingSubnodePersistence.materialize(
        WritingSubnodeWrite(path: путь, contents: Data("выход за область\n".utf8)),
        cloneURL: кореньЧекаута
      )
      дополнительныеОбъявленныеПути.append(путь)
    }
    if режим == .неуспешнаяПроверка,
      let результат = план.записи.first(where: { $0.path.hasPrefix("Результаты/цепочка/") })
    {
      try WritingSubnodePersistence.materialize(
        WritingSubnodeWrite(path: результат.path, contents: Data("подмена результата\n".utf8)),
        cloneURL: кореньЧекаута
      )
    }
    _ = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["add", "--all"], корень: кореньЧекаута
    )
    let выводПроверки = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["diff", "--cached", "--check", допуск.база, "--"],
      корень: кореньЧекаута
    )
    guard
      let записьРезультата = план.записи.first(where: {
        $0.path.hasPrefix("Результаты/цепочка/")
      })
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Шаг не объявил проверяемый результат."
      )
    }
    let хэшРезультата = СодержимоеФикстурыВозобновляемойЦепочки.хэш(
      try Data(contentsOf: кореньЧекаута.appendingPathComponent(записьРезультата.path))
    )
    guard хэшРезультата == план.хэшПроверки else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Фактический результат не прошёл детерминированную проверку."
      )
    }
    let свидетельствоПроверки: [String: Any] = [
      "схема": "fum.свидетельство-проверки-шага.1",
      "идентификатор": план.идентификаторПроверки,
      "команда": "git diff --cached --check",
      "код_завершения": 0,
      "хэш_вывода": СодержимоеФикстурыВозобновляемойЦепочки.хэш(Data(выводПроверки.utf8)),
      "хэш_результата": хэшРезультата,
    ]
    let данныеСвидетельства = try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(
      свидетельствоПроверки
    )
    let путьСвидетельства = "Паспорта/проверки/\(план.идентификаторКарточки).json"
    try WritingSubnodePersistence.materialize(
      WritingSubnodeWrite(path: путьСвидетельства, contents: данныеСвидетельства),
      cloneURL: кореньЧекаута
    )
    _ = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["add", "--all"], корень: кореньЧекаута
    )
    let путьПакета = "Пакеты/шагов/\(план.идентификаторКарточки).json"
    let объявленныеПути =
      (план.записи.map(\.path) + план.удаления
      + [план.путьПаспорта, путьПакета, путьСвидетельства]
      + дополнительныеОбъявленныеПути).sorted()
    let описаниеПакета: [String: Any] = [
      "схема": "fum.рабочий-пакет-шага-конечной-цепочки.1",
      "идентификатор_карточки": план.идентификаторКарточки,
      "хэш_карточки": план.хэшКарточки,
      "базовая_вершина": допуск.база,
      "записи": план.записи.map(\.path).sorted(),
      "удаления": план.удаления.sorted(),
      "путь_паспорта": план.путьПаспорта,
      "путь_пакета": путьПакета,
      "путь_свидетельства_проверки": путьСвидетельства,
      "объявленные_пути": объявленныеПути,
      "проверка": план.идентификаторПроверки,
    ]
    let данныеПакета = try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(
      описаниеПакета
    )
    let хэшПакета = СодержимоеФикстурыВозобновляемойЦепочки.хэш(данныеПакета)
    let паспорт: [String: Any] = [
      "схема": "fum.частный-паспорт-шага-конечной-цепочки.1",
      "идентификатор": "паспорт.шага.\(план.идентификаторКарточки)",
      "идентификатор_карточки": план.идентификаторКарточки,
      "хэш_карточки": план.хэшКарточки,
      "базовая_вершина": допуск.база,
      "путь_пакета": путьПакета,
      "хэш_пакета": хэшПакета,
      "токены": план.токены,
      "секунды": план.секунды,
      "изменённые_файлы": план.изменённыеФайлы,
      "проверки": [
        [
          "идентификатор": план.идентификаторПроверки,
          "исход": "успешно",
          "хэш_свидетельства": СодержимоеФикстурыВозобновляемойЦепочки.хэш(данныеСвидетельства),
        ]
      ],
      "объявленные_пути": объявленныеПути,
    ]
    try WritingSubnodePersistence.materialize(
      WritingSubnodeWrite(path: путьПакета, contents: данныеПакета),
      cloneURL: кореньЧекаута
    )
    try WritingSubnodePersistence.materialize(
      WritingSubnodeWrite(
        path: план.путьПаспорта,
        contents: try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(паспорт)
      ),
      cloneURL: кореньЧекаута
    )
    _ = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["add", "--all"], корень: кореньЧекаута
    )
    let фактическиеПути = try ИнструментыВозобновляемойЦепочки.данныеГит(
      ["diff", "--cached", "--no-renames", "--name-only", "-z", допуск.база, "--"],
      корень: кореньЧекаута
    ).split(separator: 0).compactMap { String(data: Data($0), encoding: .utf8) }.sorted()
    guard фактическиеПути == объявленныеПути,
      фактическиеПути.count == план.изменённыеФайлы,
      фактическиеПути.allSatisfy(путьВходитВГраницы)
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Фактический staged diff \(фактическиеПути) не совпал с объявленным пакетом \(объявленныеПути) и границами."
      )
    }
    let незаписанные = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["status", "--porcelain=v1", "--untracked-files=all"],
      корень: кореньЧекаута
    )
    for строкаСтатуса in незаписанные.split(separator: "\n") {
      guard строкаСтатуса.count >= 2,
        строкаСтатуса[строкаСтатуса.startIndex] != "?",
        строкаСтатуса[строкаСтатуса.index(after: строкаСтатуса.startIndex)] == " "
      else {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Перед созданием продолжения остались незаписанные изменения."
        )
      }
    }
  }

  private func путьВходитВГраницы(_ путь: String) -> Bool {
    let разрешённыеОснования = ["Планирование/", "Паспорта/", "Пакеты/", "Результаты/"]
    return разрешённыеОснования.contains(where: путь.hasPrefix)
      && !путь.hasPrefix("Планирование/секреты/")
      && !путь.hasPrefix("Планирование/архив/")
  }

  private func запуститьПрисоединениеПродолжения(
    _ идентификатор: String
  ) throws -> [String: Any] {
    let процесс = Process()
    процесс.executableURL = исполняемыйФайлПробника
    процесс.arguments = [
      "цепочка", "продолжение", кореньЧекаута.path, кореньУправления.path, идентификатор,
    ]
    процесс.currentDirectoryURL = кореньЧекаута
    var окружение = ProcessInfo.processInfo.environment.filter {
      !$0.key.uppercased().hasPrefix("GIT_")
    }
    окружение["GIT_CONFIG_NOSYSTEM"] = "1"
    окружение["GIT_CONFIG_GLOBAL"] = WritingSubnodeSystemRuntime.nullDevicePath
    окружение["GIT_OPTIONAL_LOCKS"] = "0"
    окружение["GIT_TERMINAL_PROMPT"] = "0"
    окружение["LC_ALL"] = "C"
    процесс.environment = окружение
    процесс.standardOutput = FileHandle.nullDevice
    процесс.standardError = FileHandle.nullDevice
    процесс.standardInput = FileHandle.nullDevice
    try процесс.run()
    let идентификаторПроцесса = процесс.processIdentifier
    let адресОжидания = адресСвидетельстваОжидания(кореньУправления, задача: идентификатор)
    let адресОшибки = адресОшибкиСессии(кореньУправления, задача: идентификатор)
    let крайнийСрок = Date().addingTimeInterval(30)
    while Date() < крайнийСрок {
      if FileManager.default.fileExists(atPath: адресОжидания.path) {
        let ожидание = try КодированиеВозобновляемойЦепочки.объект(
          WritingSubnodePersistence.readStableRegularFile(
            at: адресОжидания, maximumBytes: 128 * 1_024
          )
        )
        guard try целое(ожидание, "идентификатор_процесса") == Int(идентификаторПроцесса) else {
          throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
            "FIFO-билет опубликован не созданным host-процессом."
          )
        }
        return ожидание
      }
      if FileManager.default.fileExists(atPath: адресОшибки.path) {
        let ошибка = try КодированиеВозобновляемойЦепочки.объект(
          WritingSubnodePersistence.readStableRegularFile(
            at: адресОшибки, maximumBytes: 128 * 1_024
          )
        )
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Продолжение завершилось до публикации билета: \(ошибка)"
        )
      }
      Thread.sleep(forTimeInterval: 0.02)
    }
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
      "Продолжение не опубликовало FIFO-билет за 30 секунд."
    )
  }

  private func проверитьОжиданиеПродолжения(
    _ ожидание: [String: Any],
    идентификатор: String,
    допуск: ДопускВозобновляемойЦепочки
  ) throws {
    guard try строка(ожидание, "state") == "waiting",
      try строка(ожидание, "task_id") == идентификатор,
      try строка(ожидание, "acknowledged_head") == допуск.база,
      try строка(ожидание, "worktree_id") == допуск.рабочаяКопия,
      try строка(ожидание, "branch_ref") == допуск.ветка
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Host-задача не доказала точный ожидающий билет продолжения."
      )
    }
  }

  private func записатьСозданиеЗадачи(
    родитель: String,
    вид: String,
    идентификатор: String?,
    исход: String
  ) throws {
    let каталог = кореньУправления.appendingPathComponent("создания", isDirectory: true)
    try WritingSubnodePersistence.ensurePlainDirectory(каталог)
    let имя = "\(вид)-\(хэшКомпонента(родитель)).json"
    let адрес = каталог.appendingPathComponent(имя)
    var объект: [String: Any] = [
      "схема": "fum.создание-задачи-конечной-цепочки.1",
      "родитель": родитель,
      "вид": вид,
      "исход": исход,
    ]
    объект["идентификатор"] = идентификатор ?? NSNull()
    try WritingSubnodePersistence.persistExclusive(
      try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(объект),
      at: адрес
    )
  }

  private func восстановитьСвязанныйКоммит(
    идентификаторЗадачи: String,
    режим: РежимСессииВозобновляемойЦепочки
  ) throws -> РезультатСессииВозобновляемойЦепочки {
    guard let (исходнаяПопытка, объектПопытки) = try загрузитьПопытку(идентификаторЗадачи) else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Незарегистрированная задача не имеет подтверждённой попытки."
      )
    }
    var попытка = исходнаяПопытка
    let состояние = try строка(попытка, "состояние")
    guard состояние == "продолжение_подтверждено" || состояние == "коммит_подтверждён" else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.неоднозначноеСоздание
    }
    let сообщение = try строка(попытка, "сообщение_коммита")
    if режим == .изменённыйПовтор {
      let изменённыйХэш = СодержимоеФикстурыВозобновляемойЦепочки.хэш(
        Data((сообщение + " с изменением\n").utf8)
      )
      guard
        изменённыйХэш
          == (try строка(попытка, "хэш_сообщения"))
      else {
        let стараяВершина = try строка(попытка, "базовая_вершина")
        let новаяВершина =
          try необязательнаяСтрока(попытка, "новая_вершина")
          ?? стараяВершина
        return результат(
          исход: "conflict",
          состояниеСелектора: "не_вызван_при_точном_повторе",
          задача: идентификаторЗадачи,
          стараяВершина: стараяВершина,
          новаяВершина: новаяВершина,
          продолжение: try необязательнаяСтрока(попытка, "идентификатор_продолжения"),
          квитанция: nil,
          очередь: try необязательнаяСтрока(попытка, "объект_очереди_коммита"),
          рабочаяКопия: try строка(попытка, "идентификатор_рабочей_копии"),
          ветка: try строка(попытка, "рабочая_ссылка"),
          диапазон: nil
        )
      }
    }
    let продолжение = try строка(попытка, "идентификатор_продолжения")
    if состояние == "продолжение_подтверждено" {
      let текущаяВершина = try ИнструментыВозобновляемойЦепочки.текстГит(
        ["rev-parse", "HEAD"], корень: кореньЧекаута
      )
      if текущаяВершина == (try строка(попытка, "базовая_вершина")) {
        try проверитьТекущееДерево(попытка)
      }
    }
    let повтор = try ИнструментыВозобновляемойЦепочки.очередь(
      корень: кореньЧекаута,
      аргументы: [
        "commit", "--task-id", идентификаторЗадачи,
        "--generation", try строка(попытка, "поколение"),
        "--идентификатор-продолжения", продолжение,
        "--message", сообщение,
        "--json",
      ]
    )
    guard try строка(повтор.объект, "state") == "committed" else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Точный повтор связанного коммита вернул \(повтор.объект)."
      )
    }
    try проверитьЗаписанныйКоммит(повтор.объект, попытка: попытка)
    if состояние != "коммит_подтверждён" {
      попытка["состояние"] = "коммит_подтверждён"
      попытка["новая_вершина"] = try строка(повтор.объект, "new_head")
      попытка["ссылка_квитанции"] = try строка(повтор.объект, "ссылка_квитанции")
      попытка["объект_квитанции"] = try строка(повтор.объект, "объект_квитанции")
      попытка["объект_очереди_коммита"] = try строка(повтор.объект, "queue_oid")
      _ = try обновитьПопытку(
        попытка,
        ссылка: ссылкаПопытки(идентификаторЗадачи),
        прежнийОбъект: объектПопытки
      )
    }
    return результат(
      исход: "committed",
      состояниеСелектора: "не_вызван_при_точном_повторе",
      задача: идентификаторЗадачи,
      стараяВершина: try строка(повтор.объект, "old_head"),
      новаяВершина: try строка(повтор.объект, "new_head"),
      продолжение: продолжение,
      квитанция: повтор.объект,
      очередь: try необязательнаяСтрока(повтор.объект, "queue_oid"),
      рабочаяКопия: try строка(попытка, "идентификатор_рабочей_копии"),
      ветка: try строка(попытка, "рабочая_ссылка"),
      диапазон: nil
    )
  }

  private func проверитьТекущееДерево(_ попытка: [String: Any]) throws {
    let фактическоеДерево = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["write-tree"], корень: кореньЧекаута
    )
    guard фактическоеДерево == (try строка(попытка, "дерево")) else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.конфликтПовтора
    }
  }

  private func проверитьЗаписанныйКоммит(
    _ ответ: [String: Any],
    попытка: [String: Any]
  ) throws {
    let вершина = try строка(ответ, "new_head")
    let дерево = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["rev-parse", "\(вершина)^{tree}"], корень: кореньЧекаута
    )
    let сообщение = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["log", "-1", "--format=%B", вершина], корень: кореньЧекаута
    )
    let ожидаемоеДерево = try строка(попытка, "дерево")
    let ожидаемыйХэшСообщения = try строка(попытка, "хэш_сообщения")
    let фактическийХэшСообщения = СодержимоеФикстурыВозобновляемойЦепочки.хэш(
      Data((сообщение.precomposedStringWithCanonicalMapping + "\n").utf8)
    )
    guard дерево == ожидаемоеДерево,
      фактическийХэшСообщения == ожидаемыйХэшСообщения
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Связанный коммит не совпал с сохранённым отпечатком: дерево \(дерево)/\(ожидаемоеДерево), сообщение \(фактическийХэшСообщения)/\(ожидаемыйХэшСообщения)."
      )
    }
  }

  private func сохранитьНовуюПопытку(
    _ попытка: [String: Any],
    задача: String
  ) throws -> (String, String) {
    let ссылка = ссылкаПопытки(задача)
    if try ИнструментыВозобновляемойЦепочки.прочитатьСсылкуСтруктурированныхДанных(
      ссылка, корень: кореньЧекаута
    ) != nil {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.конфликтПовтора
    }
    let объект = try ИнструментыВозобновляемойЦепочки.записатьСсылкуСтруктурированныхДанных(
      попытка,
      ссылка: ссылка,
      прежнийОбъект: nil,
      корень: кореньЧекаута
    )
    return (объект, ссылка)
  }

  private func обновитьПопытку(
    _ попытка: [String: Any],
    ссылка: String,
    прежнийОбъект: String
  ) throws -> String {
    try ИнструментыВозобновляемойЦепочки.записатьСсылкуСтруктурированныхДанных(
      попытка,
      ссылка: ссылка,
      прежнийОбъект: прежнийОбъект,
      корень: кореньЧекаута
    )
  }

  private func загрузитьПопытку(
    _ задача: String
  ) throws -> ([String: Any], String)? {
    try ИнструментыВозобновляемойЦепочки.прочитатьСсылкуСтруктурированныхДанных(
      ссылкаПопытки(задача),
      корень: кореньЧекаута
    )
  }

  private func ссылкаПопытки(_ задача: String) -> String {
    "refs/fum/попытки-продолжений-конечной-цепочки/\(хэшКомпонента(задача))"
  }

  private func ссылкаДопуска(_ задача: String) -> String {
    ссылкаДопускаКонечнойЦепочки(задача)
  }

  private func хэшКомпонента(_ значение: String) -> String {
    SHA256.hash(data: Data(значение.utf8)).map { String(format: "%02x", $0) }.joined()
  }

  private func результат(
    исход: String,
    состояниеСелектора: String,
    задача: String,
    стараяВершина: String,
    новаяВершина: String,
    продолжение: String?,
    квитанция: [String: Any]?,
    очередь: String?,
    рабочаяКопия: String,
    ветка: String,
    диапазон: МатериализованныйДиапазонВозобновляемойЦепочки?
  ) -> РезультатСессииВозобновляемойЦепочки {
    РезультатСессииВозобновляемойЦепочки(
      исход: исход,
      состояниеСелектора: состояниеСелектора,
      идентификаторЗадачи: задача,
      идентификаторПроцесса: getpid(),
      стараяВершина: стараяВершина,
      новаяВершина: новаяВершина,
      идентификаторПродолжения: продолжение,
      ссылкаКвитанции: квитанция.flatMap { try? строка($0, "ссылка_квитанции") },
      объектКвитанции: квитанция.flatMap { try? строка($0, "объект_квитанции") },
      объектОчереди: очередь,
      идентификаторРабочейКопии: рабочаяКопия,
      рабочаяСсылка: ветка,
      ссылкаПакетаПередачи: диапазон?.ссылка,
      объектПакетаПередачи: диапазон?.объект,
      проверкаДелегирования: диапазон?.решениеПроверки
    )
  }
}


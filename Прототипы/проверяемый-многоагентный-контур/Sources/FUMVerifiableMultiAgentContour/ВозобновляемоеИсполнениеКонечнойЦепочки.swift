        "Детерминированный реестр не знает карточку \(идентификаторКарточки)."
      )
    }
  }

  static func хэш(_ данные: Data) -> String {
    "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
  }

  private static func записать(_ текст: String, путь: String, в корень: URL) throws {
    let адрес = корень.appendingPathComponent(путь)
    try FileManager.default.createDirectory(
      at: адрес.deletingLastPathComponent(),
      withIntermediateDirectories: true
    )
    try Data(текст.utf8).write(to: адрес, options: .atomic)
  }

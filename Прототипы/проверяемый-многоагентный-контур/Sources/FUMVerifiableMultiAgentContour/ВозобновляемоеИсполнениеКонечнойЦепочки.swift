public enum ОшибкаВозобновляемогоИсполненияКонечнойЦепочки:
  Error, Sendable
{
  case неверныйОтвет(String)
  case нарушениеПротокола(String)
  case командаНеВыполнена([String], Int32, String)
  case неоднозначноеСоздание
  case конфликтПовтора

  public func пояснение() -> String {
    switch self {
    case .неверныйОтвет(let пояснение):
      "Неверный ответ локального инструмента: \(пояснение)"
    case .нарушениеПротокола(let пояснение):
      "Нарушен протокол конечной цепочки: \(пояснение)"
    case .командаНеВыполнена(let аргументы, let код, let вывод):
      "Команда \(аргументы.joined(separator: " ")) завершилась с кодом \(код): \(вывод)"
    case .неоднозначноеСоздание:
      "Ответ создания продолжения неоднозначен; автоматический повтор запрещён."
    case .конфликтПовтора:
      "Повтор подготовленного перехода отличается от сохранённого отпечатка."
    }
  }
}

public enum КомандыВозобновляемойКонечнойЦепочки {
  public static func присоединиться(
    кореньЧекаута: URL,
    идентификаторЗадачи: String
  ) throws -> Data {
    let ответ = try ИнструментыВозобновляемойЦепочки.очередь(
      корень: кореньЧекаута,
      аргументы: ["join", "--task-id", идентификаторЗадачи, "--json"]
    )
    guard try строка(ответ.объект, "state") == "waiting" else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Созданное продолжение не получило ожидающий FIFO-билет."
      )
    }
    return ответ.данные
  }

  public static func выполнитьСессию(
    кореньЧекаута: URL,
    кореньУправления: URL,
    идентификаторЗадачи: String,
    исполняемыйФайлПробника: URL,
    режим: РежимСессииВозобновляемойЦепочки
  ) throws -> РезультатСессииВозобновляемойЦепочки {
    try выполнитьСессию(
      кореньЧекаута: кореньЧекаута,
      кореньУправления: кореньУправления,
      идентификаторЗадачи: идентификаторЗадачи,
      исполняемыйФайлПробника: исполняемыйФайлПробника,
      режим: режим,
      начальныйОтветОчереди: nil
    )
  }

  static func выполнитьСессию(
    кореньЧекаута: URL,
    кореньУправления: URL,
    идентификаторЗадачи: String,
    исполняемыйФайлПробника: URL,
    режим: РежимСессииВозобновляемойЦепочки,
    начальныйОтветОчереди: [String: Any]?
  ) throws -> РезультатСессииВозобновляемойЦепочки {
    try ВозобновляемыйИсполнительКонечнойЦепочки(
      кореньЧекаута: кореньЧекаута,
      кореньУправления: кореньУправления,
      исполняемыйФайлПробника: исполняемыйФайлПробника
    ).выполнитьСессию(
      идентификаторЗадачи: идентификаторЗадачи,
      режим: режим,
      начальныйОтветОчереди: начальныйОтветОчереди
    )
  }

  public static func выполнитьПродолжение(
    кореньЧекаута: URL,
    кореньУправления: URL,
    идентификаторЗадачи: String,
    исполняемыйФайлПробника: URL
  ) throws -> РезультатСессииВозобновляемойЦепочки {
    do {
      let адресСуществующегоРезультата = адресРезультатаСессии(
        кореньУправления,
        задача: идентификаторЗадачи
      )
      if FileManager.default.fileExists(atPath: адресСуществующегоРезультата.path) {
        return try JSONDecoder().decode(
          РезультатСессииВозобновляемойЦепочки.self,
          from: WritingSubnodePersistence.readStableRegularFile(
            at: адресСуществующегоРезультата,
            maximumBytes: 256 * 1_024
          )
        )
      }
      if try существуетДопуск(идентификаторЗадачи, корень: кореньЧекаута) {
        let результат = try выполнитьСессию(
          кореньЧекаута: кореньЧекаута,
          кореньУправления: кореньУправления,
          идентификаторЗадачи: идентификаторЗадачи,
          исполняемыйФайлПробника: исполняемыйФайлПробника,
          режим: .обычный,
          начальныйОтветОчереди: nil
        )
        try записатьИлиСверитьРезультат(
          результат,
          по: адресСуществующегоРезультата
        )
        return результат
      }
      let присоединение = try ИнструментыВозобновляемойЦепочки.очередь(
        корень: кореньЧекаута,
        аргументы: ["join", "--task-id", идентификаторЗадачи, "--json"]
      )
      let состояниеПрисоединения = try строка(присоединение.объект, "state")
      guard ["waiting", "reload_required", "admitted"].contains(состояниеПрисоединения)
      else {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Процесс продолжения не получил сохранённый FIFO-билет или допуск."
        )
      }
      try записатьИлиСверитьСвидетельствоОжидания(
        присоединение.объект,
        задача: идентификаторЗадачи,
        кореньУправления: кореньУправления
      )
      let результат = try выполнитьСессию(
        кореньЧекаута: кореньЧекаута,
        кореньУправления: кореньУправления,
        идентификаторЗадачи: идентификаторЗадачи,
        исполняемыйФайлПробника: исполняемыйФайлПробника,
        режим: .обычный,
        начальныйОтветОчереди: присоединение.объект
      )
      let адресРезультата = адресРезультатаСессии(
        кореньУправления,
        задача: идентификаторЗадачи
      )
      try записатьИлиСверитьРезультат(результат, по: адресРезультата)
      return результат
    } catch {
      let объект: [String: Any] = [
        "схема": "fum.ошибка-сессии-конечной-цепочки.1",
        "идентификатор_задачи": идентификаторЗадачи,
        "идентификатор_процесса": Int(getpid()),
        "описание": String(describing: error),
      ]
      try? записатьНовоеСвидетельство(
        объект,
        по: адресОшибкиСессии(кореньУправления, задача: идентификаторЗадачи)
      )
      throw error
    }
  }
}

func адресСвидетельстваОжидания(_ корень: URL, задача: String) -> URL {
  корень.appendingPathComponent("ожидания", isDirectory: true)
    .appendingPathComponent("\(хэшЗадачиДляПути(задача)).json")
}

func адресРезультатаСессии(_ корень: URL, задача: String) -> URL {
  корень.appendingPathComponent("результаты-сессий", isDirectory: true)
    .appendingPathComponent("\(хэшЗадачиДляПути(задача)).json")
}

func адресОшибкиСессии(_ корень: URL, задача: String) -> URL {
  корень.appendingPathComponent("ошибки-сессий", isDirectory: true)
    .appendingPathComponent("\(хэшЗадачиДляПути(задача)).json")
}

private func хэшЗадачиДляПути(_ задача: String) -> String {
  SHA256.hash(data: Data(задача.utf8)).map { String(format: "%02x", $0) }.joined()
}

private func записатьНовоеСвидетельство(_ объект: [String: Any], по адрес: URL) throws {
  try WritingSubnodePersistence.ensurePlainDirectory(адрес.deletingLastPathComponent())
  try WritingSubnodePersistence.persistExclusive(
    try КодированиеВозобновляемойЦепочки.каноническиеДанныеОбъекта(объект),
    at: адрес
  )
}

private func записатьИлиСверитьСвидетельствоОжидания(
  _ ответОчереди: [String: Any],
  задача: String,
  кореньУправления: URL
) throws {
  let адрес = адресСвидетельстваОжидания(кореньУправления, задача: задача)
  if FileManager.default.fileExists(atPath: адрес.path) {
    let сохранённое = try КодированиеВозобновляемойЦепочки.объект(
      WritingSubnodePersistence.readStableRegularFile(
        at: адрес,
        maximumBytes: 256 * 1_024
      )
    )
    guard try строка(сохранённое, "state") == "waiting",
      try строка(сохранённое, "task_id") == строка(ответОчереди, "task_id"),
      try строка(сохранённое, "ticket_id") == строка(ответОчереди, "ticket_id"),
      try целое(сохранённое, "seq") == целое(ответОчереди, "seq"),
      try строка(сохранённое, "worktree_id") == строка(ответОчереди, "worktree_id"),
      try строка(сохранённое, "branch_ref") == строка(ответОчереди, "branch_ref")
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.конфликтПовтора
    }
    return
  }
  guard try строка(ответОчереди, "state") == "waiting" else {
    throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
      "Возобновление продолжения не нашло исходное свидетельство waiting."
    )
  }
  var свидетельство = ответОчереди
  свидетельство["идентификатор_процесса"] = Int(getpid())
  try записатьНовоеСвидетельство(свидетельство, по: адрес)
}

private func существуетДопуск(_ задача: String, корень: URL) throws -> Bool {
  try ИнструментыВозобновляемойЦепочки.прочитатьСсылкуСтруктурированныхДанных(
    ссылкаДопускаКонечнойЦепочки(задача),
    корень: корень
  ) != nil
}

private func записатьИлиСверитьРезультат(
  _ результат: РезультатСессииВозобновляемойЦепочки,
  по адрес: URL
) throws {
  let данные = try результат.каноническиеДанные()
  try WritingSubnodePersistence.ensurePlainDirectory(адрес.deletingLastPathComponent())
  if FileManager.default.fileExists(atPath: адрес.path) {
    guard
      try WritingSubnodePersistence.readStableRegularFile(
        at: адрес,
        maximumBytes: 256 * 1_024
      ) == данные
    else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.конфликтПовтора
    }
    return
  }
  try WritingSubnodePersistence.persistExclusive(данные, at: адрес)
}

func ссылкаДопускаКонечнойЦепочки(_ задача: String) -> String {
  let компонент = SHA256.hash(data: Data(задача.utf8)).map {
    String(format: "%02x", $0)
  }.joined()
  return "refs/fum/допуски-конечной-цепочки/\(компонент)"
}


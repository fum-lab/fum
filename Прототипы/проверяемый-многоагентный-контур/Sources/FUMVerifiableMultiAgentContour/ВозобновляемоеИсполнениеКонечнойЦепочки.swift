private struct ВозобновляемыйИсполнительКонечнойЦепочки: Sendable {
  let кореньЧекаута: URL
  let кореньУправления: URL
  let исполняемыйФайлПробника: URL

  func выполнитьСессию(
    идентификаторЗадачи: String,
    режим: РежимСессииВозобновляемойЦепочки,
    начальныйОтветОчереди: [String: Any]?
  ) throws -> РезультатСессииВозобновляемойЦепочки {
    if let (попытка, _) = try загрузитьПопытку(идентификаторЗадачи) {
      let состояние = try строка(попытка, "состояние")
      if состояние == "вызов_начат" {
        let вершина = try строка(попытка, "базовая_вершина")
        return результат(
          исход: "blocked",
          состояниеСелектора: "не_вызван_при_возобновлении",
          задача: идентификаторЗадачи,
          стараяВершина: вершина,
          новаяВершина: вершина,
          продолжение: nil,
          квитанция: nil,
          очередь: try необязательнаяСтрока(попытка, "объект_очереди_подтверждения"),
          рабочаяКопия: try строка(попытка, "идентификатор_рабочей_копии"),
          ветка: try строка(попытка, "рабочая_ссылка"),
          диапазон: nil
        )
      }
      if состояние == "продолжение_подтверждено" || состояние == "коммит_подтверждён" {
        return try восстановитьСвязанныйКоммит(
          идентификаторЗадачи: идентификаторЗадачи,
          режим: режим
        )
      }
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Сохранённая попытка имеет неизвестное состояние."
      )
    }

    if let восстановленныйФинал = try восстановитьФинальноеЗавершение(
      идентификаторЗадачи: идентификаторЗадачи
    ) {
      return восстановленныйФинал
    }

    let присоединение: [String: Any]
    if let начальныйОтветОчереди {
      присоединение = начальныйОтветОчереди
    } else {
      присоединение = try ИнструментыВозобновляемойЦепочки.очередь(
        корень: кореньЧекаута,
        аргументы: ["join", "--task-id", идентификаторЗадачи, "--json"]
      ).объект
    }
    let состояниеПрисоединения = try строка(присоединение, "state")

    if состояниеПрисоединения == "not_registered" {
      return try восстановитьСвязанныйКоммит(
        идентификаторЗадачи: идентификаторЗадачи,
        режим: режим
      )
    }

    let допуск = try получитьДопуск(
      из: присоединение,
      идентификаторЗадачи: идентификаторЗадачи
    )
    try сохранитьДопускЕслиНовый(допуск)

    let селектор = try ИнструментыВозобновляемойЦепочки.селектор(
      корень: кореньЧекаута
    )
    let состояниеСелектора = try строка(селектор.объект, "state")
    if состояниеСелектора == "not_ready" {
      let завершение = try ИнструментыВозобновляемойЦепочки.очередь(
        корень: кореньЧекаута,
        аргументы: [
          "finish-clean", "--task-id", идентификаторЗадачи,
          "--generation", допуск.поколение, "--json",
        ]
      )
      guard try строка(завершение.объект, "state") == "finished_clean" else {
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Финальная сессия не получила finished_clean."
        )
      }
      let диапазон = try СборкаЖивогоДиапазонаВозобновляемойЦепочки.материализовать(
        кореньЧекаута: кореньЧекаута,
        кореньУправления: кореньУправления,
        финальноеЗавершение: завершение.объект
      )
      return результат(
        исход: "finished_clean",
        состояниеСелектора: состояниеСелектора,
        задача: идентификаторЗадачи,
        стараяВершина: допуск.база,
        новаяВершина: допуск.база,
        продолжение: nil,
        квитанция: nil,
        очередь: try необязательнаяСтрока(завершение.объект, "queue_oid"),
        рабочаяКопия: допуск.рабочаяКопия,
        ветка: допуск.ветка,
        диапазон: диапазон
      )
    }
    guard состояниеСелектора == "ready" else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Селектор вернул недопустимое состояние \(состояниеСелектора)."
      )
    }

    let идентификаторКарточки = try строка(селектор.объект, "card_id")
    let хэшКарточки = try строка(селектор.объект, "card_content_sha256")
    let план = try СодержимоеФикстурыВозобновляемойЦепочки.построитьПлан(
      идентификаторКарточки: идентификаторКарточки,
      хэшКарточки: хэшКарточки,
      рабочаяСсылка: допуск.ветка,
      корень: кореньЧекаута
    )
    try проверитьОстатокБюджета(для: план)
    try подготовитьИзменения(план, допуск: допуск, режим: режим)

    let дерево = try ИнструментыВозобновляемойЦепочки.текстГит(
      ["write-tree"], корень: кореньЧекаута
    )
    var попытка: [String: Any] = [
      "схема": "fum.попытка-продолжения-конечной-цепочки.1",
      "состояние": "вызов_начат",
      "идентификатор_задачи": идентификаторЗадачи,
      "идентификатор_карточки": план.идентификаторКарточки,
      "хэш_карточки": план.хэшКарточки,
      "поколение": допуск.поколение,
      "базовая_вершина": допуск.база,
      "рабочая_ссылка": допуск.ветка,
      "идентификатор_рабочей_копии": допуск.рабочаяКопия,
      "дерево": дерево,
      "сообщение_коммита": план.сообщениеКоммита,
      "хэш_сообщения": СодержимоеФикстурыВозобновляемойЦепочки.хэш(
        Data((план.сообщениеКоммита.precomposedStringWithCanonicalMapping + "\n").utf8)
      ),
      "идентификатор_процесса": Int(getpid()),
    ]
    let (объектНачатойПопытки, ссылкаПопытки) = try сохранитьНовуюПопытку(
      попытка,
      задача: идентификаторЗадачи
    )

    try записатьСозданиеЗадачи(
      родитель: идентификаторЗадачи,
      вид: "продолжение",
      идентификатор: режим == .неоднозначноеСоздание
        ? nil : план.идентификаторПродолжения,
      исход: режим == .неоднозначноеСоздание ? "неоднозначно" : "создана"
    )
    if режим == .неоднозначноеСоздание {
      return результат(
        исход: "blocked",
        состояниеСелектора: состояниеСелектора,
        задача: идентификаторЗадачи,
        стараяВершина: допуск.база,
        новаяВершина: допуск.база,
        продолжение: nil,
        квитанция: nil,
        очередь: допуск.объектОчереди,
        рабочаяКопия: допуск.рабочаяКопия,
        ветка: допуск.ветка,
        диапазон: nil
      )
    }

    let ожидание = try запуститьПрисоединениеПродолжения(
      план.идентификаторПродолжения
    )
    try проверитьОжиданиеПродолжения(
      ожидание,
      идентификатор: план.идентификаторПродолжения,
      допуск: допуск
    )
    попытка["состояние"] = "продолжение_подтверждено"
    попытка["идентификатор_продолжения"] = план.идентификаторПродолжения
    попытка["идентификатор_билета_продолжения"] = try строка(ожидание, "ticket_id")
    попытка["номер_билета_продолжения"] = try целое(ожидание, "seq")
    попытка["подтверждённая_вершина_продолжения"] = try строка(
      ожидание, "acknowledged_head")
    попытка["объект_очереди_подтверждения"] = try строка(ожидание, "queue_oid")
    let объектПодтверждённойПопытки = try обновитьПопытку(
      попытка,
      ссылка: ссылкаПопытки,
      прежнийОбъект: объектНачатойПопытки
    )
    if режим == .остановитьсяПослеПодтвержденияПродолжения {
      return результат(
        исход: "continuation_confirmed",
        состояниеСелектора: состояниеСелектора,
        задача: идентификаторЗадачи,
        стараяВершина: допуск.база,
        новаяВершина: допуск.база,
        продолжение: план.идентификаторПродолжения,
        квитанция: nil,
        очередь: try необязательнаяСтрока(ожидание, "queue_oid"),
        рабочаяКопия: допуск.рабочаяКопия,
        ветка: допуск.ветка,
        диапазон: nil
      )
    }

    try проверитьТекущееДерево(попытка)

    let коммит = try ИнструментыВозобновляемойЦепочки.очередь(
      корень: кореньЧекаута,
      аргументы: [
        "commit", "--task-id", идентификаторЗадачи,
        "--generation", допуск.поколение,
        "--идентификатор-продолжения", план.идентификаторПродолжения,
        "--message", план.сообщениеКоммита,
        "--json",
      ]
    )
    guard try строка(коммит.объект, "state") == "committed" else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
        "Связанный commit не завершился состоянием committed."
      )
    }
    if режим == .потерятьОтветКоммита {
      return результат(
        исход: "commit_response_lost",
        состояниеСелектора: состояниеСелектора,
        задача: идентификаторЗадачи,
        стараяВершина: допуск.база,
        новаяВершина: try строка(коммит.объект, "new_head"),
        продолжение: план.идентификаторПродолжения,
        квитанция: коммит.объект,
        очередь: try необязательнаяСтрока(коммит.объект, "queue_oid"),
        рабочаяКопия: допуск.рабочаяКопия,
        ветка: допуск.ветка,
        диапазон: nil
      )
    }

    попытка["состояние"] = "коммит_подтверждён"
    попытка["новая_вершина"] = try строка(коммит.объект, "new_head")
    попытка["ссылка_квитанции"] = try строка(коммит.объект, "ссылка_квитанции")
    попытка["объект_квитанции"] = try строка(коммит.объект, "объект_квитанции")
    попытка["объект_очереди_коммита"] = try строка(коммит.объект, "queue_oid")
    _ = try обновитьПопытку(
      попытка,
      ссылка: ссылкаПопытки,
      прежнийОбъект: объектПодтверждённойПопытки
    )

    return результат(
      исход: "committed",
      состояниеСелектора: состояниеСелектора,
      задача: идентификаторЗадачи,
      стараяВершина: допуск.база,
      новаяВершина: try строка(коммит.объект, "new_head"),
      продолжение: план.идентификаторПродолжения,
      квитанция: коммит.объект,
      очередь: try необязательнаяСтрока(коммит.объект, "queue_oid"),
      рабочаяКопия: допуск.рабочаяКопия,
      ветка: допуск.ветка,
      диапазон: nil
    )
  }

  private func получитьДопуск(
    из исходныйОтвет: [String: Any],
    идентификаторЗадачи: String
  ) throws -> ДопускВозобновляемойЦепочки {
    var ответ = исходныйОтвет
    while true {
      switch try строка(ответ, "state") {
      case "admitted":
        return try ДопускВозобновляемойЦепочки(ответ)
      case "waiting":
        ответ = try ИнструментыВозобновляемойЦепочки.очередь(
          корень: кореньЧекаута,
          аргументы: [
            "wait-until-actionable", "--task-id", идентификаторЗадачи, "--json",
          ]
        ).объект
      case "reload_required":
        let текущаяВершина = try строка(ответ, "current_head")
        try перечитатьКонтрактыИзВершины(текущаяВершина)
        let подтверждение = try ИнструментыВозобновляемойЦепочки.очередь(
          корень: кореньЧекаута,
          аргументы: [
            "ack-head", "--task-id", идентификаторЗадачи,
            "--head", текущаяВершина, "--json",
          ]
        )
        guard try строка(подтверждение.объект, "state") == "acknowledged" else {
          throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
            "Новый HEAD не подтверждён."
          )
        }
        ответ = try ИнструментыВозобновляемойЦепочки.очередь(
          корень: кореньЧекаута,
          аргументы: [
            "wait-until-actionable", "--task-id", идентификаторЗадачи, "--json",
          ]
        ).объект
      default:
        throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.нарушениеПротокола(
          "Сессия не получила допуска FIFO."
        )
      }
    }
  }

  private func восстановитьФинальноеЗавершение(
    идентификаторЗадачи: String
  ) throws -> РезультатСессииВозобновляемойЦепочки? {
    guard
      let (допуск, _) =
        try ИнструментыВозобновляемойЦепочки
        .прочитатьСсылкуСтруктурированныхДанных(
          ссылкаДопускаКонечнойЦепочки(идентификаторЗадачи),
          корень: кореньЧекаута
        )
    else { return nil }
    let селектор = try ИнструментыВозобновляемойЦепочки.селектор(корень: кореньЧекаута)
    guard try строка(селектор.объект, "state") == "not_ready" else { return nil }
    let завершение = try ИнструментыВозобновляемойЦепочки.очередь(
      корень: кореньЧекаута,
      аргументы: [
        "finish-clean", "--task-id", идентификаторЗадачи,
        "--generation", try строка(допуск, "поколение"), "--json",
      ]
    )
    guard try строка(завершение.объект, "state") == "finished_clean" else {
      throw ОшибкаВозобновляемогоИсполненияКонечнойЦепочки.конфликтПовтора
    }
    let диапазон = try СборкаЖивогоДиапазонаВозобновляемойЦепочки.материализовать(
      кореньЧекаута: кореньЧекаута,
      кореньУправления: кореньУправления,
      финальноеЗавершение: завершение.объект
    )
    let вершина = try строка(допуск, "базовая_вершина")
    return результат(
      исход: "finished_clean",
      состояниеСелектора: "not_ready",
      задача: идентификаторЗадачи,
      стараяВершина: вершина,
      новаяВершина: вершина,
      продолжение: nil,
      квитанция: nil,
      очередь: try необязательнаяСтрока(завершение.объект, "queue_oid"),
      рабочаяКопия: try строка(допуск, "идентификатор_рабочей_копии"),
      ветка: try строка(допуск, "рабочая_ссылка"),

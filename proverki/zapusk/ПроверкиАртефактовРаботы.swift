private func создатьСреду() throws -> URL {
    let путь = FileManager.default.temporaryDirectory.resolvingSymlinksInPath()
        .appendingPathComponent("fuma-a12-\(UUID().uuidString)", isDirectory: true)
    try FileManager.default.createDirectory(at: путь, withIntermediateDirectories: false)
    try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: путь.path)
    return путь
}

private final class СчётчикСинхронизаций: @unchecked Sendable {
    private let замок = NSLock()
    private var вызовы = 0
    private let отказатьПриПервомВызове: Bool

    init(отказатьПриПервомВызове: Bool) {
        self.отказатьПриПервомВызове = отказатьПриПервомВызове
    }

    var числоВызовов: Int {
        замок.lock()
        defer { замок.unlock() }
        return вызовы
    }

    func синхронизировать(_ дескриптор: Int32) throws {
        замок.lock()
        вызовы += 1
        let номер = вызовы
        замок.unlock()
        if отказатьПриПервомВызове && номер == 1 { throw ОшибкаКонтейнера.система(EIO) }
        if fsync(дескриптор) != 0 { throw ОшибкаКонтейнера.система(errno) }
    }
}

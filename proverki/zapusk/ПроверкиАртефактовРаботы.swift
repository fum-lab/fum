private struct ПолезнаяНагрузка: Codable, Equatable, Sendable {
    let вопрос: String
    let ответ: String
}

private struct НагрузкаСНестабильнымКодированием: Codable, Equatable, Sendable {
    let элементы: Set<String>
    let обратныйПорядок: Bool

    private enum Ключи: String, CodingKey { case элементы }

    static func == (левая: Self, правая: Self) -> Bool { левая.элементы == правая.элементы }

    init(элементы: Set<String>, обратныйПорядок: Bool) {
        self.элементы = элементы
        self.обратныйПорядок = обратныйПорядок
    }

    init(from источник: Decoder) throws {
        let контейнер = try источник.container(keyedBy: Ключи.self)
        элементы = Set(try контейнер.decode([String].self, forKey: .элементы))
        обратныйПорядок = false
    }

    func encode(to кодировщик: Encoder) throws {
        var контейнер = кодировщик.container(keyedBy: Ключи.self)
        let отсортированныеЭлементы = элементы.sorted()
        let закодированныеЭлементы = обратныйПорядок
            ? Array(отсортированныеЭлементы.reversed()) : отсортированныеЭлементы
        try контейнер.encode(закодированныеЭлементы, forKey: .элементы)
    }
}


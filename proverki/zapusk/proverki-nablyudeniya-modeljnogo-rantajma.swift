import Foundation
import Testing
import ОсноваЗапуска

@Suite("Наблюдение модельного runtime")
struct ПроверкиНаблюденияМодельногоРантайма {
    @Test("Разделяет запрос FUMA, выбор клиента и неизвестное подтверждение backend")
    func разделениеИсточников() throws {
        let момент = Date(timeIntervalSince1970: 1_800_000_000.125)
        let неизвестно = ПолеМодели(значение: nil, источник: "backend не наблюдался", время: nil, состояние: .неизвестно)
        let снимок = СнимокМодельногоРантайма(
            идентификаторНаблюдателя: "fuma-local", идентификаторRuntime: "session-fixture-1",
            модельFUMA: ПолеМодели(значение: "gpt-6-luna", источник: "запрос FUMA", время: момент, состояние: .актуально),
            модельКлиента: ПолеМодели(значение: "gpt-6-sol", источник: "фикстура клиента", время: момент, состояние: .актуально),
            модельBackend: неизвестно,
            усилиеFUMA: ПолеМодели(значение: "low", источник: "запрос FUMA", время: момент, состояние: .актуально),
            усилиеКлиента: ПолеМодели(значение: "medium", источник: "фикстура клиента", время: момент, состояние: .актуально),
            усилиеBackend: неизвестно)
        let обратно = try СнимокМодельногоРантайма.декодировать(снимок.кодировать())
        #expect(обратно == снимок)
        #expect(обратно.модельFUMA.значение != обратно.модельКлиента.значение)
        #expect(обратно.модельBackend.состояние == .неизвестно)
        #expect(обратно.идентификаторНаблюдателя != обратно.идентификаторRuntime)
    }

    @Test("Неизвестное, stale и конфликт не выводятся из косвенных сигналов")
    func классификацияСостояния() {
        let сейчас = Date(timeIntervalSince1970: 1_800_000_100)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: nil, подтверждённое: nil,
            время: сейчас, срокСекунд: 60, сейчас: сейчас) == .неизвестно)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: nil,
            время: сейчас.addingTimeInterval(-61), срокСекунд: 60, сейчас: сейчас) == .устарело)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "b", подтверждённое: "c",
            время: сейчас, срокСекунд: 60, сейчас: сейчас) == .конфликт)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: "a",
            время: сейчас, срокСекунд: 60, сейчас: сейчас) == .актуально)
    }

    @Test("Отсутствующая и будущая метка времени остаются неизвестными")
    func неизвестноеВремя() {
        let сейчас = Date(timeIntervalSince1970: 1_800_000_100)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: "a",
            время: nil, срокСекунд: 60, сейчас: сейчас) == .неизвестно)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: "a",
            время: сейчас.addingTimeInterval(0.001), срокСекунд: 60, сейчас: сейчас) == .неизвестно)
    }

    @Test("Клиентское значение не подтверждает backend")
    func backendОстаётсяНеизвестным() {
        let сейчас = Date(timeIntervalSince1970: 1_800_000_100)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: nil,
            время: сейчас, срокСекунд: 60, сейчас: сейчас) == .неизвестно)
    }

    @Test("Окно актуальности замкнуто и не принимает невалидный срок")
    func границыСрока() {
        let сейчас = Date(timeIntervalSince1970: 1_800_000_100)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: "a",
            время: сейчас.addingTimeInterval(-60), срокСекунд: 60, сейчас: сейчас) == .актуально)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: "a",
            время: сейчас.addingTimeInterval(-60.001), срокСекунд: 60, сейчас: сейчас) == .устарело)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: "a",
            время: сейчас, срокСекунд: -1, сейчас: сейчас) == .неизвестно)
        #expect(НаблюдательМодельногоРантайма.состояние(желательное: "a", выбранное: "a", подтверждённое: "a",
            время: сейчас, срокСекунд: .infinity, сейчас: сейчас) == .неизвестно)
    }
}

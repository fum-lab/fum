import Foundation
import Testing

@Suite("Offline-адаптер внешнего агента", .serialized)
struct ПроверкиАдаптераВнешнегоАгента {
    private func байтыФикстуры() throws -> Data {
        guard let путь = ProcessInfo.processInfo.environment["FUMA_GROK_BUILD_ACP_FIXTURE"] else {
            throw ОшибкаПроверки.нетФикстуры
        }
        return try Data(contentsOf: URL(fileURLWithPath: путь))
    }

    private func кадрыФикстуры() throws -> [КадрВнешнегоАгента] {
        var декодер = ДекодерКадровВнешнегоАгента()
        var кадры: [КадрВнешнегоАгента] = []
        for байт in try байтыФикстуры() {
            кадры.append(contentsOf: try декодер.принять(Data([байт])))
        }
        кадры.append(contentsOf: try декодер.завершить())
        return кадры
    }

    private func задача() throws -> ИдентификаторЗадачиФУМА {
        try ИдентификаторЗадачиФУМА("fuma-synthetic-task-1")
    }

    private func полномочия() throws -> ПолномочияВнешнегоАгента {
        try ПолномочияВнешнегоАгента(
            путиЧтения: ["/synthetic/read"],
            путиЗаписи: ["/synthetic/write"],
            команды: ["git status --short"],
            сетьРазрешена: false,
            пределСекунд: 30
        )
    }

    private func синтетическоеСвидетельство(
        подпискаПодтверждена: Bool = true,
        запаснойПутьКлючаИсключён: Bool = true
    ) throws -> СвидетельствоКлиентаВнешнегоАгента {
        try СвидетельствоКлиентаВнешнегоАгента(
            исполняемыйФайл: "/synthetic/grok",
            хэшИсполняемогоФайла: String(repeating: "a", count: 64),
            идентификаторИсходника: String(repeating: "b", count: 40),
            подпискаПодтверждена: подпискаПодтверждена,
            запаснойПутьКлючаИсключён: запаснойПутьКлючаИсключён,
            автообновлениеОтключено: true,
            хэшПроверки: String(repeating: "c", count: 64)
        )
    }

    private func автоматДоСессии(
        _ кадры: [КадрВнешнегоАгента]
    ) throws -> АвтоматСессииВнешнегоАгента {
        var автомат = АвтоматСессииВнешнегоАгента(задача: try задача())
        try автомат.отметитьОтправкуИнициализации(.init(1))
        try автомат.принятьОтветИнициализации(кадры[0])
        try автомат.отметитьОтправкуСозданияСессии(.init(2))
        try автомат.принятьОтветСозданияСессии(кадры[1])
        return автомат
    }

    @Test("Фикстура разбирается при фрагментации до одного байта")
    func фрагментацияКадров() throws {
        let кадры = try кадрыФикстуры()
        #expect(кадры.count == 4)
        #expect(кадры[0].вид == .ответ(.init(1)))
        #expect(кадры[1].вид == .ответ(.init(2)))
        #expect(кадры[2].вид == .уведомление("session/update"))
        #expect(кадры[3].вид == .ответ(.init(3)))
        #expect(кадры.allSatisfy { !$0.исходныеБайты.isEmpty })
    }

    @Test("Незавершённый кадр закрывается отказом")
    func незавершённыйКадр() throws {
        var декодер = ДекодерКадровВнешнегоАгента()
        _ = try декодер.принять(Data(#"{"jsonrpc":"2.0","id":1}"#.utf8))
        do {
            _ = try декодер.завершить()
            Issue.record("Незавершённый кадр принят")
        } catch let ошибка as ОшибкаКадраВнешнегоАгента {
            #expect(ошибка == .неполныйКадр)
        }
    }

    @Test("Без подтверждённого клиента подготовка закрыто отказывает")
    func нетКлиента() throws {
        let решение = ПодготовкаАдаптераВнешнегоАгента.подготовить(
            задача: try задача(),
            полномочия: try полномочия(),
            свидетельство: nil,
            окружение: [:],
            конфигурация: Data("{}\n".utf8)
        )
        guard case .отказ(.клиентНеПодтверждён) = решение else {
            Issue.record("Отсутствующий клиент не дал закрытый отказ")
            return
        }
    }

    @Test("API-key окружение запрещено без чтения значения")
    func ключВОкружении() throws {
        let решение = ПодготовкаАдаптераВнешнегоАгента.подготовить(
            задача: try задача(),
            полномочия: try полномочия(),
            свидетельство: try синтетическоеСвидетельство(),
            окружение: ["XAI_API_KEY": "synthetic-not-a-secret"],
            конфигурация: Data("{}\n".utf8)
        )
        guard case .отказ(.небезопасноеОкружение) = решение else {
            Issue.record("API-key окружение не было отклонено")
            return
        }
    }

    @Test("Неизвестная конфигурация запрещена")
    func неизвестнаяКонфигурация() throws {
        let решение = ПодготовкаАдаптераВнешнегоАгента.подготовить(
            задача: try задача(),
            полномочия: try полномочия(),
            свидетельство: try синтетическоеСвидетельство(),
            окружение: ["HOME": "/synthetic/home"],
            конфигурация: Data(#"{"api_key":"synthetic"}"#.utf8)
        )
        guard case .отказ(.неподтверждённаяКонфигурация) = решение else {
            Issue.record("Неизвестная конфигурация не была отклонена")
            return
        }
    }

    @Test("Неподтверждённый запасной API-путь запрещён")
    func запаснойПутьКлючаНеИсключён() throws {
        let решение = ПодготовкаАдаптераВнешнегоАгента.подготовить(
            задача: try задача(),
            полномочия: try полномочия(),
            свидетельство: try синтетическоеСвидетельство(
                запаснойПутьКлючаИсключён: false
            ),
            окружение: [:],
            конфигурация: Data("{}\n".utf8)
        )
        guard case .отказ(.запаснойПутьКлючаНеИсключён) = решение else {
            Issue.record("Неподтверждённый запасной API-путь не был отклонён")
            return
        }
    }

    @Test("Неизвестная переменная окружения запрещена")
    func неизвестнаяПеременнаяОкружения() throws {
        let решение = ПодготовкаАдаптераВнешнегоАгента.подготовить(
            задача: try задача(),
            полномочия: try полномочия(),
            свидетельство: try синтетическоеСвидетельство(),
            окружение: ["PATH": "/synthetic/bin"],
            конфигурация: Data("{}\n".utf8)
        )
        guard case .отказ(.небезопасноеОкружение) = решение else {
            Issue.record("Неизвестная переменная окружения не была отклонена")
            return
        }
    }

    @Test("Синтетическое свидетельство только подготавливает argv")
    func подготовкаБезЗапуска() throws {
        let задача = try задача()
        let полномочия = try полномочия()
        let решение = ПодготовкаАдаптераВнешнегоАгента.подготовить(
            задача: задача,
            полномочия: полномочия,
            свидетельство: try синтетическоеСвидетельство(),
            окружение: ["HOME": "/synthetic/home", "LANG": "C.UTF-8"],
            конфигурация: Data("{}\n".utf8)
        )
        guard case .разрешено(let запуск) = решение else {
            Issue.record("Синтетическое безопасное свидетельство не подготовило запуск")
            return
        }
        #expect(запуск.задача == задача)
        #expect(запуск.сессия == nil)
        #expect(запуск.аргументы == ["agent", "stdio"])
        #expect(!запуск.используетОболочку)
        #expect(запуск.полномочия == полномочия)
    }

    @Test("Задача FUMA и внешняя сессия остаются разными")
    func отдельныеИдентификаторы() throws {
        let кадры = try кадрыФикстуры()
        var автомат = try автоматДоСессии(кадры)
        let задача = автомат.задача
        let сессия = try #require(автомат.сессия)
        #expect(задача.значение != сессия.значение)
        try автомат.отметитьОтправкуЗапроса(.init(3))
        let событие = try #require(try автомат.принятьСобытие(кадры[2]))
        #expect(событие.задача == задача)
        #expect(событие.сессия == сессия)
        try автомат.принятьОтветЗапроса(кадры[3])
        #expect(автомат.состояние == .завершено(задача, сессия))
    }

    @Test("Чужая session/update закрыто отклоняется")
    func чужаяСессия() throws {
        let кадры = try кадрыФикстуры()
        var автомат = try автоматДоСессии(кадры)
        try автомат.отметитьОтправкуЗапроса(.init(3))
        var декодер = ДекодерКадровВнешнегоАгента()
        let чужой = try #require(try декодер.принять(Data(
            "{\"jsonrpc\":\"2.0\",\"method\":\"session/update\",\"params\":{\"sessionId\":\"other-session\"}}\n".utf8
        )).first)
        do {
            _ = try автомат.принятьСобытие(чужой)
            Issue.record("Событие чужой сессии принято")
        } catch let ошибка as ОшибкаСессииВнешнегоАгента {
            #expect(ошибка == .несовпадениеСессии)
        }
    }

    @Test("Разрыв после prompt сохраняет UNKNOWN")
    func неизвестныйИсходПослеЗапроса() throws {
        let кадры = try кадрыФикстуры()
        var автомат = try автоматДоСессии(кадры)
        try автомат.отметитьОтправкуЗапроса(.init(3))
        автомат.отметитьЗакрытиеПотока()
        let сессия = try #require(автомат.сессия)
        #expect(автомат.состояние == .неизвестныйИсход(автомат.задача, сессия))
    }

    @Test("Отмена адресуется внешней сессии, а задача остаётся локальной")
    func отмена() throws {
        let кадры = try кадрыФикстуры()
        var автомат = try автоматДоСессии(кадры)
        try автомат.отметитьОтправкуЗапроса(.init(3))
        let сессия = try #require(автомат.сессия)
        let данные = try автомат.запроситьОтмену()
        let объект = try #require(
            JSONSerialization.jsonObject(with: Data(данные.dropLast())) as? [String: Any]
        )
        let параметры = try #require(объект["params"] as? [String: Any])
        #expect(объект["method"] as? String == "session/cancel")
        #expect(параметры["sessionId"] as? String == сессия.значение)
        #expect(автомат.состояние == .отменаЗапрошена(автомат.задача, сессия, .init(3)))
    }

    enum ОшибкаПроверки: Error {
        case нетФикстуры
    }
}

import Foundation
import Testing

@Suite("Offline-адаптер внешнего агента", .serialized)
struct ПроверкиАдаптераВнешнегоАгента {
    private func байтыФикстуры() throws -> Data {
        guard let путь = ProcessInfo.processInfo.environment["FUMA_GROK_BUILD_ACP_FIXTURE"] else {
            throw ОшибкаПроверки.нетФикстуры
        }
        return try Data(contentsOf: URL(fileURLWithPath: путь))
    }

    private func кадрыФикстуры() throws -> [КадрВнешнегоАгента] {
        var декодер = ДекодерКадровВнешнегоАгента()
        var кадры: [КадрВнешнегоАгента] = []
        for байт in try байтыФикстуры() {
            кадры.append(contentsOf: try декодер.принять(Data([байт])))
        }
        кадры.append(contentsOf: try декодер.завершить())
        return кадры
    }

    private func задача() throws -> ИдентификаторЗадачиФУМА {
        try ИдентификаторЗадачиФУМА("fuma-synthetic-task-1")
    }

    private func полномочия() throws -> ПолномочияВнешнегоАгента {
        try ПолномочияВнешнегоАгента(
            путиЧтения: ["/synthetic/read"],
            путиЗаписи: ["/synthetic/write"],
            команды: ["git status --short"],
            сетьРазрешена: false,
            пределСекунд: 30
        )
    }

    private func синтетическоеСвидетельство(
        подпискаПодтверждена: Bool = true,
        запаснойПутьКлючаИсключён: Bool = true
    ) throws -> СвидетельствоКлиентаВнешнегоАгента {
        try СвидетельствоКлиентаВнешнегоАгента(
            исполняемыйФайл: "/synthetic/grok",
            хэшИсполняемогоФайла: String(repeating: "a", count: 64),
            идентификаторИсходника: String(repeating: "b", count: 40),
            подпискаПодтверждена: подпискаПодтверждена,
            запаснойПутьКлючаИсключён: запаснойПутьКлючаИсключён,
            автообновлениеОтключено: true,
            хэшПроверки: String(repeating: "c", count: 64)
        )
    }

    private func автоматДоСессии(
        _ кадры: [КадрВнешнегоАгента]
    ) throws -> АвтоматСессииВнешнегоАгента {
        var автомат = АвтоматСессииВнешнегоАгента(задача: try задача())
        try автомат.отметитьОтправкуИнициализации(.init(1))
        try автомат.принятьОтветИнициализации(кадры[0])
        try автомат.отметитьОтправкуСозданияСессии(.init(2))
        try автомат.принятьОтветСозданияСессии(кадры[1])
        return автомат
    }

    @Test("Фикстура разбирается при фрагментации до одного байта")
    func фрагментацияКадров() throws {
        let кадры = try кадрыФикстуры()
        #expect(кадры.count == 4)
        #expect(кадры[0].вид == .ответ(.init(1)))
        #expect(кадры[1].вид == .ответ(.init(2)))
        #expect(кадры[2].вид == .уведомление("session/update"))
        #expect(кадры[3].вид == .ответ(.init(3)))
        #expect(кадры.allSatisfy { !$0.исходныеБайты.isEmpty })
    }

    @Test("Незавершённый кадр закрывается отказом")
    func незавершённыйКадр() throws {
        var декодер = ДекодерКадровВнешнегоАгента()
        _ = try декодер.принять(Data(#"{"jsonrpc":"2.0","id":1}"#.utf8))
        do {
            _ = try декодер.завершить()
            Issue.record("Незавершённый кадр принят")
        } catch let ошибка as ОшибкаКадраВнешнегоАгента {
            #expect(ошибка == .неполныйКадр)
        }
    }

    @Test("Без подтверждённого клиента подготовка закрыто отказывает")
    func нетКлиента() throws {
        let решение = ПодготовкаАдаптераВнешнегоАгента.подготовить(

    @Test("Отмена адресуется внешней сессии, а задача остаётся локальной")
    func отмена() throws {
        let кадры = try кадрыФикстуры()
        var автомат = try автоматДоСессии(кадры)
        try автомат.отметитьОтправкуЗапроса(.init(3))
        let сессия = try #require(автомат.сессия)
        let данные = try автомат.запроситьОтмену()
        let объект = try #require(
            JSONSerialization.jsonObject(with: Data(данные.dropLast())) as? [String: Any]
        )
        let параметры = try #require(объект["params"] as? [String: Any])
        #expect(объект["method"] as? String == "session/cancel")
        #expect(параметры["sessionId"] as? String == сессия.значение)
        #expect(автомат.состояние == .отменаЗапрошена(автомат.задача, сессия, .init(3)))
    }

    @Test("Корректный кадр до повреждённого не исчезает")
    func корректныйИПовреждённый() throws {
        let корректный = Data("{\"jsonrpc\":\"2.0\",\"id\":1,\"result\":{}}\n".utf8)
        let повреждённый = Data("{broken}\n".utf8)
        var декодер = ДекодерКадровВнешнегоАгента()
        do {
            _ = try декодер.принять(корректный + повреждённый)
            Issue.record("Повреждённый кадр не отклонён")
        } catch let сбой as СбойДекодированияВнешнегоАгента {
            #expect(сбой.причина == .некорректныйДокумент)
            #expect(сбой.принятыеБайты.first == корректный)
            #expect(сбой.отклонённыеБайты == повреждённый)
            #expect(сбой.непринятыеБайты.isEmpty)
        }
    }

    @Test("Превышение лимита не уничтожает прежний неполный хвост")
    func лимитСохраняетХвост() throws {
        var декодер = ДекодерКадровВнешнегоАгента(пределБайтов: 64)
        let начало = Data("{\"jsonrpc\":\"2.0\",\"id\":1,".utf8)
        let окончание = Data("\"result\":{}}\n".utf8)
        _ = try декодер.принять(начало)
        let избыток = Data(repeating: 65, count: 65)
        do {
            _ = try декодер.принять(избыток)
            Issue.record("Превышение лимита принято")
        } catch let сбой as СбойДекодированияВнешнегоАгента {
            #expect(сбой.причина == .слишкомБольшойКадр)
            #expect(сбой.отклонённыеБайты == начало)
            #expect(сбой.непринятыеБайты == избыток)
            #expect(декодер.неполныйХвост == начало)
            let кадры = try декодер.принять(окончание)
            #expect(кадры.first?.исходныеБайты == начало + окончание)
        }
    }

    @Test("Неполный хвост сохраняется после отказа завершения")
    func завершениеСохраняетХвост() throws {
        var декодер = ДекодерКадровВнешнегоАгента()
        let начало = Data("{\"jsonrpc\":\"2.0\",\"id\":1,".utf8)
        let окончание = Data("\"result\":{}}\n".utf8)
        _ = try декодер.принять(начало)
        do {
            _ = try декодер.завершить()
            Issue.record("Неполный хвост принят как завершённый")
        } catch let ошибка as ОшибкаКадраВнешнегоАгента {
            #expect(ошибка == .неполныйКадр)
            let кадры = try декодер.принять(окончание)
            #expect(кадры.first?.исходныеБайты == начало + окончание)
        }
    }

    @Test("Кадр ошибки сохраняет точные исходные байты")
    func байтыОшибки() throws {
        let данные = Data("{ \"jsonrpc\":\"2.0\",\"id\":3,\"error\":{\"code\":-1,\"message\":\"synthetic\"} }\n".utf8)
        var декодер = ДекодерКадровВнешнегоАгента()
        let кадр = try #require(try декодер.принять(данные).first)
        #expect(кадр.вид == .ошибка(.init(3)))
        #expect(кадр.исходныеБайты == данные)
        let кадры = try кадрыФикстуры()
        var автомат = try автоматДоСессии(кадры)
        try автомат.отметитьОтправкуЗапроса(.init(3))
        do {
            try автомат.принятьОтветЗапроса(кадр)
            Issue.record("Ошибка ответа не отклонена")
        } catch let ошибка as ОшибкаСессииВнешнегоАгента {
            #expect(ошибка == .ошибкаОтвета(данные))
        }
    }


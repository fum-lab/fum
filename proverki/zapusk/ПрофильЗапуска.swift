import Foundation
import Testing
import ОсноваЗапуска

@Suite("Малый профиль корневого цикла", .serialized)
struct ПроверкиПрофиляКорневогоЗапуска {
    @Test("Три пары сохраняют процессное и полезное время отдельно")
    func малыйПрофильКорневогоЗапуска() async throws {
        struct Пара: Codable {
            let первый: НаблюдениеПроцессаЗапуска
            let повтор: НаблюдениеПроцессаЗапуска
            let полезныйЦиклПервого: UInt64
            let полезныйЦиклПовтора: UInt64
        }
        struct Профиль: Encodable {
            let схема = "fuma.профиль-корневого-цикла.1"
            let хэшБинарникаДо: String
            let хэшБинарникаПосле: String
            let граница = "Три пары процессов: Process.run до обнаружения isRunning == false, включая polling 5 мс и планировщик; без подготовки, чтения pin и синхронизации RAW вызывающей стороны. Полезный цикл измерен отдельно внутри actor. Интервалы вложены и не суммируются. Сборка отдельно. Кэш ОС не очищался; pin читает бинарник."
            let образцы: [Пара]
        }
        let среда = try СредаПроверкиЗапуска()
        let процессы = try ПроцессыЗапуска(среда: среда)
        let хэшДо = try await процессы.проверенныйХэш()
        var образцы: [Пара] = []
        for номер in 0..<3 {
            let хранилище = среда.корень.appendingPathComponent("sample-\(номер)")
            let событие = UUID().uuidString.lowercased()
            let аргументы = ["--хранилище", хранилище.path, "--событие", событие, "--профиль"]
            let первый = try await процессы.запустить(аргументы)
            try #require(первый.код == 0)
            let ответ = try JSONDecoder().decode(ОтветЗапуска.self, from: первый.вывод)
            let результат = try #require(ответ.результат)
            let файл = хранилище.appendingPathComponent("сегмент.fumobs")
            let байты = try Data(contentsOf: файл)
            let повтор = try await процессы.запустить(аргументы)
            try #require(повтор.код == 0)
            let повторённыйОтвет = try JSONDecoder().decode(ОтветЗапуска.self, from: повтор.вывод)
            let повторённый = try #require(повторённыйОтвет.результат)
            #expect(повтор.процесс != первый.процесс)
            #expect(результат.квитанция == повторённый.квитанция)
            #expect(результат.наблюдение.намерение == "открыть локальную историю")
            #expect(повторённый.изменение == .точныйПовтор)
            #expect(повторённый.принятоЗаписей == 1)
            #expect(try Data(contentsOf: файл) == байты)
            образцы.append(Пара(первый: первый, повтор: повтор,
                полезныйЦиклПервого: try #require(результат.полезныйЦиклНаносекунды),
                полезныйЦиклПовтора: try #require(повторённый.полезныйЦиклНаносекунды)))
        }
        let хэшПосле = try await процессы.проверенныйХэш()
        let профиль = Профиль(хэшБинарникаДо: хэшДо, хэшБинарникаПосле: хэшПосле, образцы: образцы)
        try ПредставлениеЗапуска.байты(профиль, читаемо: true).write(
            to: среда.корень.appendingPathComponent("профиль.json"), options: [.withoutOverwriting])
    }
}

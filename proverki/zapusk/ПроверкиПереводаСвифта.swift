    @Test func юникодИПромежуткиСохраняютсяБайтами() throws {
        let текст = "// Ёж🙂е\u{0308}\r\nlet `old` = 1\r\nprint(`old`)\r\n"
        let результат = try план(текст, карта(текст))
        #expect(результат.будущиеБайты == байты("// Ёж🙂е\u{0308}\r\nlet `русское` = 1\r\nprint(`русское`)\r\n"))
        #expect(результат.хэшНеизменныхПромежутков.count == 64)
        var исходныеПромежутки = Data()
        var будущиеПромежутки = Data()
        let исходные = байты(текст)
        var прежде = 0
        var затем = 0
        for замена in результат.замены {
            let размер = замена.начало - прежде
            исходныеПромежутки.append(исходные[прежде..<замена.начало])
            будущиеПромежутки.append(результат.будущиеБайты[затем..<(затем + размер)])
            прежде = замена.конец; затем += размер + замена.новоеИмя.utf8.count
        }
        исходныеПромежутки.append(исходные[прежде...])
        будущиеПромежутки.append(результат.будущиеБайты[затем...])
        #expect(исходныеПромежутки == будущиеПромежутки)
    }


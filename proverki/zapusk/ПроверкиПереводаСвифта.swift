    private func байты(_ текст: String) -> Data { Data(текст.utf8) }
    private func позиции(_ текст: String, _ имя: String) -> [Int] {
        let исходник = байты(текст)
        let образец = байты(имя)
        var результат: [Int] = []
        var начало = 0
        while начало < исходник.count,
              let диапазон = исходник.range(of: образец, in: начало..<исходник.count) {
            результат.append(диапазон.lowerBound); начало = диапазон.upperBound
        }
        return результат
    }
    private func карта(_ текст: String, старое: String = "old", новое: String = "русское",
        выбранные: [Int]? = nil, хэш: String? = nil) throws -> Data {
        let места = выбранные ?? позиции(текст, старое)
        let объявление: Int = try #require(места.first)
        let привязка = ПривязкаПереводаСвифта(идентификатор: "одна", староеИмя: старое,
            новоеИмя: новое, объявление: объявление, употребления: Array(места.dropFirst()))
        return try JSONEncoder().encode(КартаПереводаСвифта(схема: "fum.карта-позиций-свифт.1", файлы: [
            ФайлКартыСвифта(путь: "пример.swift", исходныйХэш: хэш ?? ПереводСвифта.хэш(байты(текст)),
                привязки: [привязка])]))
    }
    private func план(_ текст: String, _ вход: Data) throws -> ПланФайлаСвифта {
        try #require(ПереводСвифта.план(вход, исходники: ["пример.swift": байты(текст)]).файлы.first)
    }

    @Test func меняютсяТолькоВыбранныеТокеныИПростаяИнтерполяция() throws {
        let текст = "let old = 1\r\nlet ответ = \"old: \\(old)\" // old\r\nlet путь = url.path\r\n"
        let места = позиции(текст, "old")
        let результат = try план(текст, карта(текст, выбранные: [места[0], места[2]]))
        #expect(результат.будущиеБайты == байты("let русское = 1\r\nlet ответ = \"old: \\(русское)\" // old\r\nlet путь = url.path\r\n"))
        #expect(результат.замены.count == 2)
        #expect(результат.будущийХэш == ПереводСвифта.хэш(результат.будущиеБайты))
    }


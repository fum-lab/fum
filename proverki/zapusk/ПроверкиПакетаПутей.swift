import Foundation
import Testing
@testable import ОсноваЗапуска

@Suite("CLI пакета путей", .serialized)
struct ПроверкиПакетаПутей {
    private let корень = URL(fileURLWithPath: "/tmp/fuma-пакет-путей", isDirectory: true)
    private let хэш = String(repeating: "a", count: 64)

    @Test("Парсер распознаёт точные формы трёх действий")
    func формыДействий() throws {
        let построение = try РазборПакетаПутей.разобрать([
            "построить", "--корень", корень.path, "--вход", "/tmp/поручение.json"
        ])
        guard case .построить(let кореньПостроения, let вход) = построение else {
            Issue.record("Построение получило другой маршрут")
            return
        }
        #expect(кореньПостроения == корень)
        #expect(вход.path == "/tmp/поручение.json")

        let сверка = try РазборПакетаПутей.разобрать([
            "сверить", "--корень", корень.path, "--план", "/tmp/план.json", "--sha256", хэш
        ])
        guard case .сверить(let кореньСверки, let планСверки, let shaСверки) = сверка else {
            Issue.record("Сверка получила другой маршрут")
            return
        }
        #expect(кореньСверки == корень)
        #expect(планСверки.path == "/tmp/план.json")
        #expect(shaСверки == хэш)

        let применение = try РазборПакетаПутей.разобрать([
            "применить", "--корень", корень.path, "--план", "/tmp/план.json", "--sha256", хэш
        ])
        guard case .применить(let кореньПрименения, let планПрименения, let shaПрименения) = применение else {
            Issue.record("Применение получило другой маршрут")
            return
        }
        #expect(кореньПрименения == корень)
        #expect(планПрименения.path == "/tmp/план.json")
        #expect(shaПрименения == хэш)
    }

    @Test("Отсутствующие, повторные и неизвестные аргументы отклоняются до адаптера")
    func неверныеАргументыДоАдаптера() async {
        let неверные: [[String]] = [
            [],
            ["построить", "--корень", корень.path],
            ["построить", "--корень", корень.path, "--вход", "/tmp/a", "--вход", "/tmp/b"],
            ["построить", "--корень", корень.path, "--вход", "/tmp/a", "--неизвестно", "x"],
            ["сверить", "--корень", корень.path, "--план", "/tmp/план.json"],
            ["применить", "--корень", "относительный", "--план", "/tmp/план.json", "--sha256", хэш],
            ["сверить", "--корень", корень.path, "--план", "/tmp/план.json", "--sha256", String(repeating: "A", count: 64)],
            ["сверить", "--корень", корень.path, "--план", "/tmp/план.json", "--sha256", String(repeating: "a", count: 63)]
        ]
        for аргументы in неверные {
            let адаптер = АдаптерПакетаПутейДляТестов()
            let результат = await ОбработчикПакетаПутей(адаптер: адаптер).выполнить(аргументы)
            #expect(результат.код == 2)
            #expect(результат.вывод.isEmpty)
            #expect(await адаптер.вызовы.isEmpty)
        }
    }

    @Test("Построение и сверка передают точные Data и SHA; сверка не создаёт тело")
    func точныеВходыПостроенияИСверки() async throws {
        let временный = try ВременныйКаталогПакетаПутей()
        let поручение = Data([0x7b, 0x00, 0xff, 0x0a, 0x7d])
        let план = Data([0x00, 0xc3, 0x28, 0x7d])
        let ответПостроения = Data([0xff, 0x00, 0x7b])
        try поручение.write(to: временный.url.appendingPathComponent("поручение.json"))
        try план.write(to: временный.url.appendingPathComponent("план.json"))

        let адаптерПостроения = АдаптерПакетаПутейДляТестов(ответПостроения: ответПостроения)
        let результатПостроения = await ОбработчикПакетаПутей(адаптер: адаптерПостроения).выполнить([
            "построить", "--корень", корень.path, "--вход", временный.url.appendingPathComponent("поручение.json").path
        ])
        #expect(результатПостроения.код == 0)
        #expect(результатПостроения.вывод == ответПостроения)
        let вызовПостроения = try #require(await адаптерПостроения.вызовы.first)
        #expect(вызовПостроения == .построить(корень, поручение))

        let адаптерСверки = АдаптерПакетаПутейДляТестов()
        let результатСверки = await ОбработчикПакетаПутей(адаптер: адаптерСверки).выполнить([
            "сверить", "--корень", корень.path, "--план", временный.url.appendingPathComponent("план.json").path,
            "--sha256", хэш
        ])
        #expect(результатСверки.код == 0)
        #expect(результатСверки.вывод.isEmpty)
        #expect(await адаптерСверки.вызовы == [.сверить(корень, план, хэш)])
    }

    @Test("Четыре допустимых исхода сохраняют квитанцию без изменения байтов",
          arguments: ["завершено", "откат-проверен", "частичный", "неизвестно"])
    func исходыКвитанции(_ исход: String) async throws {
        let временный = try ВременныйКаталогПакетаПутей()
        let план = try временный.записать(Data([0x00, 0xff]), под: "план.json")
        let квитанция = try квитанция(исход: исход)
        let адаптер = АдаптерПакетаПутейДляТестов(ответПрименения: квитанция)
        let результат = await ОбработчикПакетаПутей(адаптер: адаптер).выполнить([
            "применить", "--корень", корень.path, "--план", план.path, "--sha256", хэш
        ])

        #expect(результат.код == (исход == "завершено" ? 0 : 2))
        #expect(результат.вывод == квитанция)
        #expect(await адаптер.вызовы == [.применить(корень, Data([0x00, 0xff]), хэш)])
    }

    @Test("Повреждённая, неизвестная или относящаяся к другому плану квитанция закрывает успех")
    func невернаяКвитанция() async throws {
        let временный = try ВременныйКаталогПакетаПутей()
        let план = try временный.записать(Data([0x7b, 0x00, 0xff]), под: "план.json")
        let другиеОтветы = [
            Data([0x7b]),
            Data(#"{"схема":"другая","план_sha256":"\#(хэш)","исход":"завершено","подтверждённый_префикс":9}"#.utf8),
            Data(#"{"схема":"fum.квитанция-пакета-девяти-путей.1","план_sha256":"\#(String(repeating: "b", count: 64))","исход":"завершено","подтверждённый_префикс":9}"#.utf8),
            Data(#"{"схема":"fum.квитанция-пакета-девяти-путей.1","план_sha256":"\#(хэш)","исход":"успех","подтверждённый_префикс":9}"#.utf8)
        ]
        for байты in другиеОтветы {
            let адаптер = АдаптерПакетаПутейДляТестов(ответПрименения: байты)
            let результат = await ОбработчикПакетаПутей(адаптер: адаптер).выполнить([
                "применить", "--корень", корень.path, "--план", план.path, "--sha256", хэш
            ])
            #expect(результат.код == 2)
            #expect(результат.вывод == байты)
            #expect(await адаптер.вызовы == [.применить(корень, Data([0x7b, 0x00, 0xff]), хэш)])
        }
    }

    @Test("Throw apply после возможного эффекта сообщает неизвестность без квитанции и повтора")
    func неизвестныйИсходApply() async throws {
        let временный = try ВременныйКаталогПакетаПутей()
        let план = try временный.записать(Data([0x10, 0x20]), под: "план.json")
        let адаптер = АдаптерПакетаПутейДляТестов(ошибкаПрименения: true)
        let результат = await ОбработчикПакетаПутей(адаптер: адаптер).выполнить([
            "применить", "--корень", корень.path, "--план", план.path, "--sha256", хэш
        ])
        #expect(результат.код == 2)
        #expect(результат.вывод.isEmpty)
        #expect(String(decoding: результат.ошибка, as: UTF8.self).contains("Исход применения неизвестен"))
        #expect(await адаптер.вызовы.count == 1)
    }

    @Test("Неизвестное действие не распознаётся")
    func неизвестноеДействие() {
        #expect(throws: ОшибкаАргументовПакетаПутей.self) {
            try РазборПакетаПутей.разобрать(["удалить", "--корень", корень.path])
        }
    }

    private func квитанция(исход: String) throws -> Data {
        let текст = """
        {"схема":"fum.квитанция-пакета-девяти-путей.1","план_sha256":"\(хэш)","исход":"\(исход)","подтверждённый_префикс":9,"наблюдённый_префикс":9}
        """
        return Data(текст.utf8)
    }
}

private final class ВременныйКаталогПакетаПутей {
    let url: URL

    init() throws {
        url = FileManager.default.temporaryDirectory
            .appendingPathComponent("fuma-пакет-путей-\(UUID().uuidString.lowercased())", isDirectory: true)
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: false)
    }

    func записать(_ данные: Data, под именем: String) throws -> URL {
        let файл = url.appendingPathComponent(именем)
        try данные.write(to: файл)
        return файл
    }

    deinit { try? FileManager.default.removeItem(at: url) }
}

private actor АдаптерПакетаПутейДляТестов: АдаптерПакетаПутей {
    enum Вызов: Sendable, Equatable {
        case построить(URL, Data)
        case сверить(URL, Data, String)
        case применить(URL, Data, String)
    }

    private let ответПостроения: Data
    private let ответПрименения: Data
    private let ошибкаПрименения: Bool
    private(set) var вызовы: [Вызов] = []

    init(ответПостроения: Data = Data(), ответПрименения: Data = Data(), ошибкаПрименения: Bool = false) {
        self.ответПостроения = ответПостроения
        self.ответПрименения = ответПрименения
        self.ошибкаПрименения = ошибкаПрименения
    }

    func построить(корень: URL, поручение: Data) async throws -> Data {
        вызовы.append(.построить(корень, поручение))
        return ответПостроения
    }

    func сверить(корень: URL, план: Data, sha256: String) async throws {
        вызовы.append(.сверить(корень, план, sha256))
    }

    func применить(корень: URL, план: Data, sha256: String) async throws -> Data {
        вызовы.append(.применить(корень, план, sha256))
        if ошибкаПрименения { throw ОшибкаПроверочногоАдаптера() }
        return ответПрименения
    }
}

private struct ОшибкаПроверочногоАдаптера: Error, Sendable {}

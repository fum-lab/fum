        let перваяПамять = try памятьДляПроверки(первый, хранилище: перваяКоробка)
        let втораяПамять = try памятьДляПроверки(второй, хранилище: втораяКоробка)

        let перваяЗапись = try await перваяПамять.сохранить(
            .генезис, время: "2026-11-03T00:04:00Z")
        let втораяЗапись = try await втораяПамять.сохранить(
            .генезис, время: "2026-11-03T00:04:00Z")

    private var количествоЗаписей = 0
    private var последнийАртефакт: String?

    init(неизвестноеПоколение: UInt64? = nil,
         сохранятьНеизвестнуюЗапись: Bool = false) {
        self.неизвестноеПоколение = неизвестноеПоколение
        self.сохранятьНеизвестнуюЗапись = сохранятьНеизвестнуюЗапись
    }

    var числоЗаписей: Int {
        блокировка.lock()
        defer { блокировка.unlock() }
        return количествоЗаписей
    }

    var последнееСостояниеA12: СостояниеПреемника? {
        блокировка.lock()
        defer { блокировка.unlock() }
        return состоянияA12.last
    }

    var последнийИдентификаторАртефакта: String? {
        блокировка.lock()
        defer { блокировка.unlock() }
        return последнийАртефакт
    }

    func сохранить(_ вход: ВходВопросОтвета) throws -> ИсходПисателяАгентаFUM {
        let байтыСобытия = Data(вход.вопрос.utf8)
        let байтыПолезнойНагрузки = Data(вход.ответ.utf8)
        let событие = try JSONDecoder().decode(
            СобытиеМаршрутаАгентаFUM.self, from: байтыСобытия)
        let полезнаяНагрузка = try JSONDecoder().decode(
            СодержимоеПамятиАгентаFUM.self, from: байтыПолезнойНагрузки)
        let идентификаторЗаписи = "fake-record-\(вход.поколение)"
        let хэшЗаписи = хэш(Data(идентификаторЗаписи.utf8))
        var байтыПерехода = байтыСобытия
        байтыПерехода.append(0)
        байтыПерехода.append(байтыПолезнойНагрузки)
        let позиция = ПозицияПамятиАгентаFUM(
            идентификаторХранилища: полезнаяНагрузка.идентификаторХранилища,
            идентификаторАгента: полезнаяНагрузка.идентификаторАгента,
            идентификаторАртефакта: вход.идентификатор,
            поколение: вход.поколение,
            идентификаторЗаписи: идентификаторЗаписи,
            sha256Записи: хэшЗаписи,
            sha256Перехода: хэш(байтыПерехода),
            предшественник: полезнаяНагрузка.предшественник)
        let восстановленная = ВосстановленнаяЗаписьАгентаFUM(
            позиция: позиция, событие: событие, снимок: полезнаяНагрузка.снимок,
            предшественник: полезнаяНагрузка.предшественник, время: вход.время)
        let исходНеизвестен = вход.поколение == неизвестноеПоколение

        блокировка.lock()
        defer { блокировка.unlock() }
        количествоЗаписей += 1
        состоянияA12.append(вход.состояние)
        последнийАртефакт = вход.идентификатор
        if !исходНеизвестен || сохранятьНеизвестнуюЗапись {
            записи[идентификаторЗаписи] = восстановленная
        }
        if исходНеизвестен {
            return .неизвестен(
                идентификаторЗаписи: идентификаторЗаписи, sha256: хэшЗаписи)
        }
        return .подтверждён(
            идентификаторЗаписи: идентификаторЗаписи, sha256: хэшЗаписи)
    }

    func восстановить(_ позиция: ПозицияПамятиАгентаFUM)
        -> ВосстановленнаяЗаписьАгентаFUM? {
        блокировка.lock()
        defer { блокировка.unlock() }
        guard let запись = записи[позиция.идентификаторЗаписи],
              запись.позиция == позиция else { return nil }
        return запись
    }

    func удалитьВсеЗаписи() {
        блокировка.lock()
        defer { блокировка.unlock() }
        записи.removeAll()
    }
}

private func памятьДляПроверки(
    _ агент: ИдентичностьАгентаFUM,
    продолжение: ПродолжениеПамятиАгентаFUM? = nil,
    хранилище: КоробкаПамятиАгентаFUM
) throws -> ПамятьАгентаFUM {
    try ПамятьАгентаFUM(
        дляПроверки: агент, продолжение: продолжение,
        записать: { вход in try хранилище.сохранить(вход) },
        прочитать: { позиция in хранилище.восстановить(позиция) })
}

private func продолжениеПослеПодтверждения(
    _ исход: ИсходСохраненияАгентаFUM
) throws -> ПродолжениеПамятиАгентаFUM {
    switch исход {
    case .подтверждён(let продолжение), .точныйПовтор(let продолжение):
        return продолжение
    case .закрытиеПодтверждено(_, let продолжение):
        return продолжение
    case .неизвестен, .удержан:
        throw ОшибкаАгентаFUM.неверноеПродолжение
    }
}

private func продолжениеПослеПерезапуска(
    _ продолжение: ПродолжениеПамятиАгентаFUM
) throws -> ПродолжениеПамятиАгентаFUM {
    let данные = try JSONEncoder().encode(продолжение)
    return try JSONDecoder().decode(ПродолжениеПамятиАгентаFUM.self, from: данные)
}

private func снимокОжидающийРешения(
    для агента: ИдентичностьАгентаFUM
) throws -> (РаботаАгентаFUM, РезультатРаботыАгентаFUM, СнимокАгентаFUM) {
    let работа = примерРаботы(для: агент)
    let генезис = try МаршрутАгентаFUM.подготовить(
        .генезис, после: .пустой(для: агент), для: агент)
    let назначение = try МаршрутАгентаFUM.подготовить(
        .назначена(работа), после: генезис, для: агент)
    let начало = try МаршрутАгентаFUM.подготовить(
        .началась(идентификаторРаботы: работа.идентификатор),
        после: назначение, для: агент)
    let результат = примерРезультата(для: работа)
    let ожидание = try МаршрутАгентаFUM.подготовить(
        .поступилРезультат(результат), после: начало, для: агент)
    return (работа, результат, ожидание)
}


            "same-agent", родитель: nil, ожидаемыйПотребитель: потребитель,
            хранилище: "store-one")
        let второй = примерАгента(
            "same-agent", родитель: nil, ожидаемыйПотребитель: потребитель,
            хранилище: "store-two")
        let перваяКоробка = КоробкаПамятиАгентаFUM()

    @Test("Найденный после перезапуска UNKNOWN связывает продолжение без новой записи")
    func неизвестнаяНоНайденнаяЗаписьСверяетсяБезПовтора() async throws {
        let агент = примерАгента(
            "root-agent", родитель: nil,
            ожидаемыйПотребитель: примерногоПотребителя())
        let работа = примерРаботы(для: агент)
        let хранилище = КоробкаПамятиАгентаFUM(
            неизвестноеПоколение: 2, сохранятьНеизвестнуюЗапись: true)
        let перваяПамять = try памятьДляПроверки(агент, хранилище: хранилище)
        let генезис = try await перваяПамять.сохранить(
            .генезис, время: "2026-11-03T00:02:00Z")
        _ = try продолжениеПослеПодтверждения(генезис)
        let назначение = try await перваяПамять.сохранить(
            .назначена(работа), время: "2026-11-03T00:02:01Z")
        guard case .неизвестен(_, let токенПродолжения) = назначение else {
            Issue.record("UNKNOWN должен сохранить адресный токен продолжения.")
            return
        }

        let восстановленноеПродолжение = try продолжениеПослеПерезапуска(
            токенПродолжения)
        let памятьПослеПерезапуска = try памятьДляПроверки(
            агент, продолжение: восстановленноеПродолжение, хранилище: хранилище)
        let сверка = try await памятьПослеПерезапуска.сверитьНеизвестнуюЗапись()
        guard case .найден(let подтверждённоеПродолжение) = сверка else {
            Issue.record("Существующий преемник должен быть найден по точному адресу.")
            return
        }
        #expect(подтверждённоеПродолжение.позиция != nil)
        #expect(подтверждённоеПродолжение.неизвестнаяЗапись == nil)
        let точныйПовтор = try await памятьПослеПерезапуска.сохранить(
            .назначена(работа), время: "2026-11-03T00:02:02Z")
        guard case .точныйПовтор = точныйПовтор else {
            Issue.record("Найденная попытка должна стать точным повтором без новой записи.")
            return
        }
        #expect(хранилище.числоЗаписей == 2)
    }

    @Test("Отсутствующий UNKNOWN после перезапуска требует решения без повтора")
    func отсутствующаяНеизвестнаяЗаписьУдерживаетсяПослеРешения() async throws {
        let потребитель = примерногоПотребителя()
        let агент = примерАгента(

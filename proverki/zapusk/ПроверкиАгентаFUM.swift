    @Test("Корень и ребёнок закрепляют точного ожидаемого потребителя")
    func идентичностьСвязываетНазначившегоИПотребителя() throws {
        let потребительКорня = СсылкаАгентаFUM(
            идентификатор: "user-01", цель: "Принимает итог корневого узла.")
        let корень = примерАгента(
            "root-agent", родитель: nil, ожидаемыйПотребитель: потребительКорня)
        let ссылкаКорня = СсылкаАгентаFUM(
            идентификатор: корень.идентификатор, цель: корень.цель)
        let ребёнок = примерАгента(
            "child-agent", родитель: ссылкаКорня, ожидаемыйПотребитель: ссылкаКорня)

        try корень.проверить()
        try ребёнок.проверить()
        #expect(корень.родитель == nil)
        #expect(корень.ожидаемыйПотребитель == потребительКорня)
        #expect(ребёнок.родитель == ребёнок.ожидаемыйПотребитель)
        #expect(ребёнок.собственнаяЗапись != корень.собственнаяЗапись)
        #expect(ребёнок.собственнаяПамять != корень.собственнаяПамять)

        let генезис = try МаршрутАгентаFUM.подготовить(
            .генезис, после: .пустой(для: корень), для: корень)
        let чужойПотребитель = СсылкаАгентаFUM(
            идентификатор: "other-consumer", цель: "Не назначенный потребитель.")
        for (назначивший, ожидаемыйПотребитель) in [
            (чужойПотребитель, потребительКорня),
            (потребительКорня, чужойПотребитель)
        ] {
            let работа = РаботаАгентаFUM(
                идентификатор: "answer", владелец: корень.идентификатор,
                версияНазначения: 1, цель: "Ответить по закреплённому входу.",
                вид: .ответитьНаВопрос,
                описание: "Назначение с проверяемой идентичностью потребителя.",
                назначивший: назначивший,
                ожидаемыйПотребитель: ожидаемыйПотребитель,
                ссылкаНазначения: примерСсылки("assignment://answer"),
                происхождение: [примерСсылки("source://question")])
            #expect(throws: ОшибкаАгентаFUM.self) {
                try МаршрутАгентаFUM.подготовить(
                    .назначена(работа), после: генезис, для: корень)
            }
        }

        let неверныйРебёнок = примерАгента(
            "child-agent", родитель: ссылкаКорня,
            ожидаемыйПотребитель: СсылкаАгентаFUM(
                идентификатор: "wrong-consumer", цель: "Не родитель ребёнка."))
        #expect(throws: ОшибкаАгентаFUM.self) { try неверныйРебёнок.проверить() }
    }

    @Test("Переход готовит закрытие; квитанция A12 подтверждает его отдельно")
    func результатИРешениеСвязаныДоКвитанцииЗакрытия() async throws {
        let потребитель = примерногоПотребителя()
        let агент = примерАгента(
            "root-agent", родитель: nil, ожидаемыйПотребитель: потребитель)
        let работа = примерРаботы(для: агент)
        let хранилище = КоробкаПамятиАгентаFUM()
        let память = try памятьДляПроверки(агент, хранилище: хранилище)

        let генезис = try await память.сохранить(
            .генезис, время: "2026-11-03T00:00:00Z")
        _ = try продолжениеПослеПодтверждения(генезис)
        let назначение = try await память.сохранить(
            .назначена(работа), время: "2026-11-03T00:00:01Z")
        _ = try продолжениеПослеПодтверждения(назначение)
        let начало = try await память.сохранить(
            .началась(идентификаторРаботы: работа.идентификатор),
            время: "2026-11-03T00:00:02Z")
        _ = try продолжениеПослеПодтверждения(начало)

        let результат = примерРезультата(для: работа)
        let переданРезультат = try await память.сохранить(
            .поступилРезультат(результат), время: "2026-11-03T00:00:03Z")
        let ожиданиеПотребителя = try продолжениеПослеПодтверждения(переданРезультат)
        #expect(ожиданиеПотребителя.снимок.состояние == .ожидаетРешенияПотребителя)

        let решение = примерОбратнойСвязи(для: работа, результат: результат,
                                         потребитель: потребитель)
        let принято = try await память.сохранить(
            .решениеПотребителя(решение), время: "2026-11-03T00:00:04Z")
        guard case .закрытиеПодтверждено(let закрытие, let продолжение) = принято else {
            Issue.record("Закрытие должно появиться после подтверждения преемника через A12.")
            return
        }
        #expect(закрытие.снимок.состояние == .готоваКЗакрытию)
        let позицияЗакрытия = try #require(продолжение.позиция)
        #expect(закрытие.квитанция == позицияЗакрытия)
        #expect(продолжение.решениеПоНеизвестнойЗаписи == nil)
        #expect(хранилище.последнееСостояниеA12 == .some(.ожидает))
        #expect(хранилище.числоЗаписей == 5)
    }


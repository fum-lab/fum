            неизвестноеПоколение: 2, сохранятьНеизвестнуюЗапись: false)
        let перваяПамять = try памятьДляПроверки(агент, хранилище: хранилище)
        let генезис = try await перваяПамять.сохранить(
            .генезис, время: "2026-11-03T00:03:00Z")
        _ = try продолжениеПослеПодтверждения(генезис)
        let назначение = try await перваяПамять.сохранить(
            .назначена(работа), время: "2026-11-03T00:03:01Z")
        guard case .неизвестен(_, let токенПродолжения) = назначение else {
            Issue.record("UNKNOWN должен сохранить попытку и предыдущий снимок.")
            return
        }

        let восстановленноеПродолжение = try продолжениеПослеПерезапуска(
            токенПродолжения)
        let памятьПослеПерезапуска = try памятьДляПроверки(
            агент, продолжение: восстановленноеПродолжение, хранилище: хранилище)
        let сверка = try await памятьПослеПерезапуска.сверитьНеизвестнуюЗапись()
        guard case .записьОтсутствует(let продолжениеБезЗаписи) = сверка else {
            Issue.record("Отсутствие должно оставаться явным результатом сверки.")
            return
        }
        #expect(продолжениеБезЗаписи.неизвестнаяЗапись != nil)
        let неверноеРешение = РешениеПослеНеизвестнойЗаписиFUM(
            позицияПопытки: try #require(токенПродолжения.неизвестнаяЗапись?.позицияПопытки.ссылка),
            потребитель: СсылкаАгентаFUM(
                идентификатор: "other-consumer", цель: "Не ожидаемый потребитель."),
            назначение: работа.ссылкаНазначения,
            наблюдение: примерСсылки("observation://2"),
            версияНаблюдаемогоСостояния: 2, основание: "Чужая граница решения.")
        await #expect(throws: ОшибкаАгентаFUM.self) {
            try await памятьПослеПерезапуска.решитьНеизвестнуюЗапись(неверноеРешение)
        }

        let решение = РешениеПослеНеизвестнойЗаписиFUM(
            позицияПопытки: try #require(токенПродолжения.неизвестнаяЗапись?.позицияПопытки.ссылка),
            потребитель: потребитель,
            назначение: работа.ссылкаНазначения,
            наблюдение: примерСсылки("observation://2"),
            версияНаблюдаемогоСостояния: 2,
            основание: "Сверка адресно подтвердила отсутствие; повтор остановлен.")
        let разрешённоеПродолжение = try await памятьПослеПерезапуска
            .решитьНеизвестнуюЗапись(решение)
        #expect(разрешённоеПродолжение.решениеПоНеизвестнойЗаписи == решение)

        let сохранённоеПродолжение = try продолжениеПослеПерезапуска(
            разрешённоеПродолжение)
        let памятьПослеВторогоПерезапуска = try памятьДляПроверки(
            агент, продолжение: сохранённоеПродолжение, хранилище: хранилище)
        let удержание = try await памятьПослеВторогоПерезапуска.сохранить(
            .назначена(работа), время: "2026-11-03T00:03:02Z")
        guard case .удержан = удержание else {
            Issue.record("Типизированное решение не должно автоматически повторять запись.")
            return
        }
        #expect(хранилище.числоЗаписей == 2)
    }


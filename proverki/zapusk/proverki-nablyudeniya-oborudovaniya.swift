struct ФиктивныйИсточникНаблюденийОборудования: ИсточникНаблюденийОборудования {
    let данные: СырыеСведенияОборудования

    func прочитать() -> СырыеСведенияОборудования {
        данные
    }
}

@Suite("Наблюдение оборудования: ограниченный контракт", .serialized)
struct ПроверкиНаблюденияОборудования {
    enum ОшибкаПроверки: Error {
        case нарушеноОжидание(строка: UInt)
    }

    static func подтвердить(
        _ условие: Bool,
        строка: UInt = #line
    ) throws {
        guard условие else { throw ОшибкаПроверки.нарушеноОжидание(строка: строка) }
    }

    static let окно = ОкноНаблюдения(
        начало: "2026-10-30T12:00:00Z",
        окончание: "2026-10-30T12:00:00.001Z",
        длительностьНаносекунд: 1_000_000
    )

    static func источник(
        версия: Результат<ВерсияОС> = .доступно(ВерсияОС(основная: 15, дополнительная: 2, исправление: 1)),
        всегоЯдер: Результат<Int> = .доступно(8),
        память: Результат<UInt64> = .доступно(16_000_000_000),
        активныеЯдра: Результат<Int> = .доступно(8),
        тепловойРежим: Результат<ТепловойРежим> = .доступно(.номинальный)
    ) -> ФиктивныйИсточникНаблюденийОборудования {
        ФиктивныйИсточникНаблюденийОборудования(данные: СырыеСведенияОборудования(
            версияОС: версия,
            числоЯдер: всегоЯдер,
            физическаяПамятьБайтов: память,
            активныеЯдра: активныеЯдра,
            тепловойРежим: тепловойРежим
        ))
    }

    static func новыйСнимок(
        из источник: ФиктивныйИсточникНаблюденийОборудования? = nil
    ) throws -> СнимокНаблюденийОборудования {
        try НаблюдательОборудования.собрать(
            из: источник ?? self.источник(),
            окно: окно
        )
    }

    static func проверитьРазделениеИМетаданные() throws {
        let снимок = try новыйСнимок()
        try снимок.проверить()

        try подтвердить(снимок.статические.map(\.имя) == [
            .версияОперационнойСистемы,
            .числоПроцессорныхЯдер,
            .физическаяПамять
        ])
        try подтвердить(снимок.динамические.map(\.имя) == [
            .активныеПроцессорныеЯдра,
            .тепловоеСостояние,
            .температура,
            .загрузкаПроцессора
        ])
        try подтвердить(снимок.статические.allSatisfy { $0.окно == окно && !$0.источник.isEmpty })
        try подтвердить(снимок.динамические.allSatisfy { $0.окно == окно && !$0.источник.isEmpty })
        try подтвердить(снимок.статические.map(\.единица) == [.версия, .ядро, .байт])
        try подтвердить(снимок.динамические.map(\.единица) == [.ядро, .категория, .градусЦельсия, .процент])
    }

    static func проверитьНеизвестныеНедоступныеИНекорректныеДанные() throws {
        let снимок = try новыйСнимок(из: источник(
            версия: .недоступно("Источник не предоставил версию."),
            всегоЯдер: .доступно(8),
            память: .неизвестно("Объём памяти не получен."),
            активныеЯдра: .доступно(12),
            тепловойРежим: .неизвестно("Состояние не получено.")
        ))

        try подтвердить(снимок.статические[0].результат.состояние == .недоступно)
        try подтвердить(снимок.статические[0].результат.значение == nil)
        try подтвердить(снимок.статические[1].результат.состояние == .доступно)
        try подтвердить(снимок.статические[1].результат.значение == .целое(8))
        try подтвердить(снимок.статические[2].результат.состояние == .неизвестно)
        try подтвердить(снимок.динамические[0].результат.состояние == .неизвестно)
        try подтвердить(снимок.динамические[1].результат.состояние == .неизвестно)
        try подтвердить(снимок.динамические[2].результат.состояние == .неизвестно)
        try подтвердить(снимок.динамические[3].результат.состояние == .неизвестно)

        let нулевоеЧислоЯдер = try новыйСнимок(из: источник(всегоЯдер: .доступно(0)))
        try подтвердить(нулевоеЧислоЯдер.статические[1].результат.состояние == .неизвестно)
    }

    static func проверитьЕдиницыИОтклонениеНеверногоЕдинства() throws {
        let снимок = try новыйСнимок()
        var статические = снимок.статические
        статические[2] = МетрикаНаблюденияОборудования(
            имя: .физическаяПамять,
            единица: .процент,
            источник: статические[2].источник,
            окно: статические[2].окно,
            результат: статические[2].результат
        )
        let неверныйСнимок = СнимокНаблюденийОборудования(
            схема: снимок.схема,
            статические: статические,
            динамические: снимок.динамические,
            покрытие: снимок.покрытие
        )

        var невернаяСтроковаяЕдиницаОтклонена = false
        do {
            _ = try JSONDecoder().decode(ЕдиницаИзмеренияОборудования.self, from: Data("\"выдуманная\"".utf8))
        } catch {
            невернаяСтроковаяЕдиницаОтклонена = true
        }
        try подтвердить(невернаяСтроковаяЕдиницаОтклонена)

        var невернаяКомбинацияОтклонена = false
        do {
            try неверныйСнимок.проверить()
        } catch {
            невернаяКомбинацияОтклонена = true
        }
        try подтвердить(невернаяКомбинацияОтклонена)
    }

    static func проверитьНеобязательноеЗначениеИJSONRoundTrip() throws {
        let снимок = try новыйСнимок()
        let байты = try снимок.форматированныеJSON()
        try подтвердить(байты.last == 0x0A)

        let восстановленный = try JSONDecoder().decode(СнимокНаблюденийОборудования.self, from: байты)
        try подтвердить(восстановленный == снимок)

        let неизвестно = Результат<UInt64>.неизвестно("Значение не измерялось.")
        let неизвестныеБайты = try JSONEncoder().encode(неизвестно)
        let неизвестныйОбъект = try JSONSerialization.jsonObject(with: неизвестныеБайты) as? [String: Any]
        try подтвердить(неизвестныйОбъект?["значение"] == nil)
        try подтвердить(try JSONDecoder().decode(Результат<UInt64>.self, from: неизвестныеБайты) == неизвестно)

        let безЯвногоЗначения = Data("{\"состояние\":\"UNKNOWN\",\"причина\":\"Значение не измерялось.\"}".utf8)
        let восстановленныйНеизвестный = try JSONDecoder().decode(Результат<UInt64>.self, from: безЯвногоЗначения)
        try подтвердить(восстановленныйНеизвестный == неизвестно)
    }

    static func проверитьОтсутствиеПолейИдентификаторов() throws {
        let данные = try JSONSerialization.jsonObject(with: try новыйСнимок().форматированныеJSON())
        var ключи: [String] = []
        var строки: [String] = []

        func собрать(_ значение: Any) {
            if let объект = значение as? [String: Any] {
                for (ключ, дочернее) in объект {
                    ключи.append(ключ.lowercased())
                    собрать(дочернее)
                }
            } else if let массив = значение as? [Any] {
                массив.forEach(собрать)
            } else if let строка = значение as? String {
                строки.append(строка.lowercased())
            }
        }
        собрать(данные)

        let признакиИдентификаторов = ["серийныйНомер", "uuid", "hostname", "macAddress", "diskIdentifier", "имяПользователя"]
        try подтвердить(ключи.allSatisfy { ключ in !признакиИдентификаторов.contains { ключ.contains($0.lowercased()) } })
        try подтвердить(строки.allSatisfy { строка in !признакиИдентификаторов.contains { строка.contains($0.lowercased()) } })
    }

    static func выполнитьВсеДляЛёгкогоЗапуска() throws {
        try проверитьРазделениеИМетаданные()
        try проверитьНеизвестныеНедоступныеИНекорректныеДанные()
        try проверитьЕдиницыИОтклонениеНеверногоЕдинства()
        try проверитьНеобязательноеЗначениеИJSONRoundTrip()
        try проверитьОтсутствиеПолейИдентификаторов()
    }

    @Test("Статические данные отделены от динамики; единицы, источник и окно явны")
    func разделениеИМетаданные() throws {
        try Self.проверитьРазделениеИМетаданные()
    }

    @Test("Недоступность, UNKNOWN и некорректные значения не подменяются нулём")
    func состоянияДанных() throws {
        try Self.проверитьНеизвестныеНедоступныеИНекорректныеДанные()
    }

    @Test("Неизвестная единица и несовместимая размерность отклоняются")
    func единицы() throws {
        try Self.проверитьЕдиницыИОтклонениеНеверногоЕдинства()
    }

    @Test("JSON round-trip сохраняет UNKNOWN без необязательного value и завершается LF")
    func roundTrip() throws {
        try Self.проверитьНеобязательноеЗначениеИJSONRoundTrip()
    }

    @Test("JSON не содержит полей или значений идентификаторов")
    func приватность() throws {
        try Self.проверитьОтсутствиеПолейИдентификаторов()
    }
}

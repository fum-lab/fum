import Foundation
import Testing
#if !ФУМ_ОБЩАЯ_МИГРАЦИЯ_ТЕСТ
@testable import АктуализацияПутей
#endif

@Suite("Общий бюджет метаданных коллекции без допуска исполнения")
struct ПроверкиУчётаАртефактов {
    let идентификатор = "01a148a5-c088-7373-9665-a3f9b477565e", профиль = String(repeating: "a", count: 64)
    func файл(_ путь: String = "base/expected.json", размер: Int = 10, роль: РольАртефактаКандидатов = .основа, хэш: String = String(repeating: "1", count: 64)) -> АртефактКандидатов {
        .init(путь: путь, хэш: хэш, размер: размер, роль: роль)
    }
    func создать(_ файлы: [АртефактКандидатов], предел: Int = 134_217_728) throws -> УчтённаяКоллекцияКандидатов {
        try УчётАртефактовКандидатов.создать(идентификатор: идентификатор, хэшПрофиля: профиль, артефакты: файлы, предел: предел)
    }
    @Test("Повторная ссылка не повторяет bytes, новая физическая копия оплачивается")
    func ссылкиИКопии() throws {
        let а = try создать([файл(), файл()]), б = try УчётАртефактовКандидатов.дополнить(а, идентификатор: идентификатор, хэшПрофиля: профиль,
            артефакты: [файл(), файл("run-a/copied-expected.json")])
        #expect(а.занято == 10 && а.артефакты.count == 1 && б.занято == 20 && б.артефакты.count == 2)
        #expect(а.занято == 10 && !б.физическиеФайлыПроверены && !б.продолжениеРазрешено && !б.применениеРазрешено)
    }
    @Test("Предел и control reserve учитывают накопленное через новое окно")
    func накопленныйБюджет() throws {
        let а = try создать([файл(размер: 60)], предел: 100)
        #expect(try а.свободноДляДанных(резервУправления: 30) == 10)
        #expect(throws: (any Error).self) { try а.свободноДляДанных(резервУправления: 41) }
        let б = try УчётАртефактовКандидатов.дополнить(а, идентификатор: идентификатор, хэшПрофиля: профиль, артефакты: [файл("run-a/window.json", размер: 40, роль: .управление)])
        #expect(б.занято == 100)
        #expect(throws: (any Error).self) { try УчётАртефактовКандидатов.дополнить(б, идентификатор: идентификатор, хэшПрофиля: профиль, артефакты: [файл("run-b/result.json", размер: 1)]) }
    }
    @Test("Hash, size и role уже учтённого пути не меняются")
    func неизменностьАртефактов() throws {
        let а = try создать([файл()])
        for другой in [файл(размер: 11), файл(роль: .журнал), файл(хэш: String(repeating: "2", count: 64))] {
            #expect(throws: (any Error).self) { try УчётАртефактовКандидатов.дополнить(а, идентификатор: идентификатор, хэшПрофиля: профиль, артефакты: [другой]) }
        }
        #expect(throws: (any Error).self) { try УчётАртефактовКандидатов.дополнить(а, идентификатор: "01a148a5-c088-7373-9665-a3f9b477565f", хэшПрофиля: профиль, артефакты: []) }
        #expect(throws: (any Error).self) { try УчётАртефактовКандидатов.дополнить(а, идентификатор: идентификатор, хэшПрофиля: String(repeating: "b", count: 64), артефакты: []) }
    }
    @Test("Неправильные paths, SHA и размеры закрываются до сложения")
    func опасныеВходы() {
        for ф in [файл("../x"), файл("a//x"), файл("A/x"), файл("каталог/x"), файл("a/../x"), файл("a\\x"), файл(размер: -1), файл(размер: Int.max), файл(размер: 33_554_433), файл(хэш: "bad"),
            файл(Array(repeating: "a", count: 65).joined(separator: "/"))] {
            #expect(throws: (any Error).self) { try создать([ф]) }
        }
        #expect(throws: (any Error).self) { try создать([], предел: 134_217_729) }
    }
    @Test("Неизвестный остаток оплачивается, сортировка и fingerprint воспроизводимы")
    func неизвестныеОстатки() throws {
        let а = файл(), б = файл("run-a/partial.json", размер: 7, роль: .неизвестныйОстаток)
        let р = try создать([а, б]), с = try создать([б, а])
        #expect(р.занято == 17 && р.содержитНеизвестныеОстатки && !р.продолжениеРазрешено)
        #expect(р.хэшСостава == с.хэшСостава && р.артефакты == с.артефакты)
    }
    @Test("Один файл не становится предком другого в создании или обновлении")
    func конфликтПрефиксов() throws {
        for файлы in [[файл("a"), файл("a/b")], [файл("a/b"), файл("a")]] {
            #expect(throws: (any Error).self) { try создать(файлы) }
            let прежний = try создать([файлы[0]])
            #expect(throws: (any Error).self) {
                try УчётАртефактовКандидатов.дополнить(прежний, идентификатор: идентификатор, хэшПрофиля: профиль, артефакты: [файлы[1]])
            }
        }
    }
    @Test("Отпечаток связывает все поля, коллекцию, профиль и неизменный предел")
    func полныйОтпечаток() throws {
        let исходный = try создать([файл()])
        for другой in [try создать([файл("other.json")]), try создать([файл(размер: 11)]), try создать([файл(роль: .журнал)]),
            try создать([файл(хэш: String(repeating: "2", count: 64))]), try создать([файл()], предел: 100)] {
            #expect(другой.хэшСостава != исходный.хэшСостава)
        }
        for (номер, профильИлиКоллекция) in ["01a148a5-c088-7373-9665-a3f9b477565f", String(repeating: "b", count: 64)].enumerated() {
            let другой = try УчётАртефактовКандидатов.создать(идентификатор: номер == 0 ? профильИлиКоллекция : идентификатор,
                хэшПрофиля: номер == 1 ? профильИлиКоллекция : профиль, артефакты: [файл()])
            #expect(другой.хэшСостава != исходный.хэшСостава)
        }
        let ссылка = try УчётАртефактовКандидатов.дополнить(исходный, идентификатор: идентификатор, хэшПрофиля: профиль, артефакты: [файл()])
        let пустой = try УчётАртефактовКандидатов.дополнить(исходный, идентификатор: идентификатор, хэшПрофиля: профиль, артефакты: [])
        #expect(ссылка.хэшСостава == исходный.хэшСостава && пустой.хэшСостава == исходный.хэшСостава)
    }
    @Test("Границы числа refs/файлов и размера принимаются без выделения тел")
    func точныеПределы() throws {
        let файлы = (0..<32_768).map { файл(String(format: "runs/f%05d.json", $0), размер: 0, роль: .результат) }
        let р = try создать(файлы, предел: 0)
        #expect(р.артефакты.count == 32_768 && р.занято == 0)
        #expect(throws: (any Error).self) { try УчётАртефактовКандидатов.дополнить(р, идентификатор: идентификатор, хэшПрофиля: профиль, артефакты: [файл("extra.json", размер: 0)]) }
        #expect(throws: (any Error).self) { try создать(Array(repeating: файл(), count: 65_537)) }
        let большой = try создать([файл(размер: 33_554_432)])
        #expect(большой.занято == 33_554_432)
    }
}

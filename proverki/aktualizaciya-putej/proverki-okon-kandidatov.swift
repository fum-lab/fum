@Suite("Последовательные окна: только согласованность переданных свидетельств")
struct ПроверкиОконКандидатов {
    let опоры = ОпорыОкнаДиагностики(коллекция: "01a148a5-c088-7373-9665-a3f9b477565e", хэшПрофиля: String(repeating: "a", count: 64),
        хэшИсточникаПроизводителя: String(repeating: "b", count: 64), хэшСредыПроизводителя: String(repeating: "c", count: 64))
    func план(_ размеры: [Int] = [1, 1, 1, 1, 1]) throws -> ПланПорцийКандидатов {
        try ПланировщикПорцийКандидатов.построить(размеры.enumerated().map { номер, размер in
            .init(путь: "документ-\(номер).md", хэш: String(repeating: "d", count: 64), режим: "100644", размер: размер,
                класс: "отслеживаемый", объект: String(repeating: "e", count: 40))
        }, хэшОжидания: String(repeating: "1", count: 64), хэшФизическогоСнимка: String(repeating: "2", count: 64),
            хэшСобственногоИсточника: String(repeating: "3", count: 64), хэшКонтекста: String(repeating: "4", count: 64), документовВПорции: 1)
    }
    func файл(_ путь: String, _ роль: РольАртефактаКандидатов = .управление, байты: Data = Data([10])) -> АртефактКандидатов {
        .init(путь: путь, хэш: хэшПутей(байты), размер: байты.count, роль: роль)
    }
    func заголовок(_ запись: ОжидаемаяЗаписьПорции) -> ЗаголовокРезультатаКандидатов {
        .init(номерДокумента: запись.номер, хэшПути: хэшПутей(Data(запись.документ.путь.utf8)), байтыПути: запись.документ.путь.utf8.count,
            хэшДокумента: запись.документ.хэш, размерДокумента: запись.документ.размер, хэшПлана: запись.хэшПлана,
            хэшКонтекста: запись.опоры.контекст, хэшОжидания: запись.опоры.ожидание, хэшФизическогоСнимка: запись.опоры.физическийСнимок,
            хэшСобственногоИсточника: запись.опоры.собственныйИсточник)
    }
    struct Вход {
        let манифест: МанифестОкнаДиагностики
        let байты: Data
        let файлМанифеста: АртефактКандидатов
        let история: [ПопыткаОкнаДиагностики]
        let учёт: УчтённаяКоллекцияКандидатов
    }
    func вход(_ план: ПланПорцийКандидатов, начало: Int = 0, число: Int = 1, голова: ГоловаПроверенногоОкна? = nil,
        метка: Int? = nil,
        изменить: (([СсылкаРезультатаКандидатов]) -> [СсылкаРезультатаКандидатов])? = nil) throws -> Вход {
        let окно = String(format: "00000000-0000-4000-8000-%012d", (метка ?? начало) + 1), каталог = "runs/r\(метка ?? начало)/"
        let намерение = файл(каталог + "intent.json")
        let началоДокументов = план.шаги[начало].начало, конец = план.шаги[начало + число - 1].конец
        let ссылки = try (началоДокументов..<конец).map { номер in
            СсылкаРезультатаКандидатов(заголовок: заголовок(try план.ожидаемаяЗапись(номер)), артефакт: файл(каталог + "d\(номер).json", .результат))
        }
        let результаты = изменить?(ссылки) ?? ссылки
        let м = МанифестОкнаДиагностики(окно: окно, опоры: опоры, хэшПлана: план.хэшСостава, хэшНамерения: намерение.хэш,
            хэшПредыдущейТочки: голова?.контрольнаяТочка.хэш, перваяПорция: начало, числоПорций: число, результаты: результаты)
        let байты = try ПроверкаОкнаКандидатов.байтыМанифеста(м), ф = файл(каталог + "manifest.json", байты: байты)
        let т = ТерминалОкнаДиагностики(окно: окно, опоры: опоры, кодВыхода: 0, хэшМанифеста: ф.хэш,
            хэшНамерения: намерение.хэш, артефакт: файл(каталог + "terminal.json"))
        let попытка = ПопыткаОкнаДиагностики(окно: окно, намерение: намерение, терминал: .обычныйВыход(т))
        let артефакты = (голова?.учёт.артефакты ?? []) + [намерение, ф, т.артефакт] + результаты.map(\.артефакт)
        return .init(манифест: м, байты: байты, файлМанифеста: ф, история: (голова?.окно.история ?? []) + [попытка],
            учёт: try УчётАртефактовКандидатов.создать(идентификатор: опоры.коллекция, хэшПрофиля: опоры.хэшПрофиля, артефакты: артефакты))
    }
    func проверить(_ в: Вход, _ п: ПланПорцийКандидатов, голова: ГоловаПроверенногоОкна? = nil,
        история: [ПопыткаОкнаДиагностики]? = nil, учёт: УчтённаяКоллекцияКандидатов? = nil, байты: Data? = nil) throws -> ПроверенноеСтруктурноеОкно {
        try ПроверкаОкнаКандидатов.проверить(план: п, опоры: опоры, предыдущая: голова.map { .голова($0) } ?? .начало,
            история: история ?? в.история, учёт: учёт ?? в.учёт, манифест: в.манифест, байтыМанифеста: байты ?? в.байты, артефактМанифеста: в.файлМанифеста)
    }
    func голова(_ окно: ПроверенноеСтруктурноеОкно) throws -> ГоловаПроверенногоОкна {
        let ф = файл("checkpoints/c\(окно.следующаяПорция).json", байты: окно.байтыКонтрольнойТочки)
        let у = try УчётАртефактовКандидатов.дополнить(окно.учёт, идентификатор: опоры.коллекция, хэшПрофиля: опоры.хэшПрофиля, артефакты: [ф])
        return try ПроверкаОкнаКандидатов.связать(окно, контрольнаяТочка: ф, учёт: у)
    }
    @Test("Начальная порция и четыре следующие сохраняют границу без полномочий")
    func последовательность() throws {
        let п = try план(), а = try проверить(вход(п), п), г = try голова(а)
        let б = try проверить(вход(п, начало: 1, число: 4, голова: г), п, голова: г)
        #expect(а.следующийДокумент == 1 && б.следующийДокумент == 5 && б.следующаяПорция == 5)
        #expect(!б.физическиеФайлыПроверены && !б.содержимоеПакетовПроверено && !б.внешняяИсторияПроверена && !б.текущаяГоловаПроверена
            && !б.терминальныйПроцессПроверен && !б.ролиПроверены
            && !б.целиПроверены && !б.запускРазрешён && !б.продолжениеРазрешено && !б.применениеРазрешено)
        #expect(а.байтыКонтрольнойТочки.last == 10 && !а.байтыКонтрольнойТочки.isEmpty)
    }
    @Test("Пропуск, повтор порции и начало без прежней головы отвергаются")
    func границы() throws {
        let п = try план(), г = try голова(проверить(вход(п), п))
        for начало in [0, 2] {
            let в = try вход(п, начало: начало, голова: г, метка: 100 + начало)
            #expect(throws: (any Error).self) { try проверить(в, п, голова: г) }
        }
        let в = try вход(п, начало: 1, голова: г)
        #expect(throws: (any Error).self) { try проверить(в, п) }
    }

    @Test("Checkpoint оплачивается один раз, подмена или лишний файл не создают голову")
    func контрольнаяТочка() throws {
        let п = try план(), окно = try проверить(вход(п), п), г = try голова(окно)
        #expect(г.учёт.занято == окно.учёт.занято + окно.байтыКонтрольнойТочки.count)
        #expect(г.учёт.артефакты.count == окно.учёт.артефакты.count + 1)
        let иной = файл("checkpoints/other.json")
        #expect(throws: (any Error).self) { try ПроверкаОкнаКандидатов.связать(окно, контрольнаяТочка: иной, учёт: г.учёт) }
        #expect(throws: (any Error).self) { try ПроверкаОкнаКандидатов.связать(окно, контрольнаяТочка: г.контрольнаяТочка, учёт: окно.учёт) }
        let лишний = try УчётАртефактовКандидатов.дополнить(г.учёт, идентификатор: опоры.коллекция, хэшПрофиля: опоры.хэшПрофиля,
            артефакты: [файл("extra/log", .журнал)])
        #expect(throws: (any Error).self) { try ПроверкаОкнаКандидатов.связать(окно, контрольнаяТочка: г.контрольнаяТочка, учёт: лишний) }
        let объект = try #require(JSONSerialization.jsonObject(with: окно.байтыКонтрольнойТочки) as? [String: Any])

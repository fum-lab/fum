    @Test("Прежние факты и предел нельзя сбросить новым созданием ledger")
    func сохранениеУчёта() throws {
        let п = try план(), г = try голова(проверить(вход(п), п)), в = try вход(п, начало: 1, голова: г)
        let у = try УчётАртефактовКандидатов.создать(идентификатор: опоры.коллекция, хэшПрофиля: опоры.хэшПрофиля,
            артефакты: в.учёт.артефакты.filter { $0.путь != г.контрольнаяТочка.путь })
        #expect(throws: (any Error).self) { try проверить(в, п, голова: г, учёт: у) }
        for способ in 0..<3 {
            let файлы = в.учёт.артефакты.compactMap { а -> АртефактКандидатов? in
                guard а.путь == "runs/r0/d0.json" else { return а }
                if способ == 0 { return nil }
                if способ == 1 { return .init(путь: а.путь, хэш: а.хэш, размер: а.размер, роль: .журнал) }
                return а
            }
            let сброшенный = try УчётАртефактовКандидатов.создать(идентификатор: опоры.коллекция, хэшПрофиля: опоры.хэшПрофиля,
                артефакты: файлы, предел: способ == 2 ? в.учёт.предел - 1 : в.учёт.предел)
            #expect(throws: (any Error).self) { try проверить(в, п, голова: г, учёт: сброшенный) }
        }
    }

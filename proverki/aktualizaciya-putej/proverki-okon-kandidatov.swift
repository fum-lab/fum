                    хэшДокумента: поле == 3 ? иной : з.хэшДокумента, размерДокумента: з.размерДокумента + (поле == 4 ? 1 : 0),
                    хэшПлана: поле == 5 ? иной : з.хэшПлана, хэшКонтекста: поле == 6 ? иной : з.хэшКонтекста,

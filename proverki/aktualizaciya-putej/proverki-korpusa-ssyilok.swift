import Foundation
import Testing
#if !ФУМ_ОБЩАЯ_МИГРАЦИЯ_ТЕСТ
@testable import АктуализацияПутей
#endif

@Suite("Закрытый корпус ссылок без утраты исходных участников")
struct ПроверкиКорпусаСсылок {
    let основа = ОсноваОбщейМиграции(корневаяЗадача: "01a07d3d-d376-7ad2-aafc-67e4c25a67eb", владелец: "фикстура",
        ветка: "refs/heads/fixture", коммит: String(repeating: "a", count: 40), дерево: String(repeating: "b", count: 40), индексSHA256: String(repeating: "c", count: 64))
    func документ(_ путь: String, _ текст: String, _ роль: РольДокументаКорпуса = .действующий) -> ДокументКорпусаМиграции {
        .init(путь: путь, байты: Data(текст.utf8), роль: роль, основаниеРоли: "явная-проверочная-роль")
    }
    func ожидание(_ путь: String, _ текст: String) -> ОжидаемыйДокументКорпуса { .init(путь: путь, хэш: ОбщийПланировщикПутей.хэш(Data(текст.utf8))) }
    func план(_ документы: [ДокументКорпусаМиграции], _ ожидаемые: [ОжидаемыйДокументКорпуса], пары: [(String, String)] = [], пути: [String]? = nil) throws -> ПланКорпусаСсылок {
        let исходные = пути ?? ожидаемые.map(\.путь), карта = Dictionary(uniqueKeysWithValues: пары.map { (Data($0.0.utf8), $0.1) })
        return try КорпусСсылокМиграции.построить(основа: основа, ожидаемаяОснова: основа, документы: документы, ожидаемые: ожидаемые,
            источникОжидаемого: "независимый-проверочный-манифест", отображения: пары.map { .init(исходный: $0.0, целевой: $0.1) },
            исходныеПути: Set(исходные.map { Data($0.utf8) }), конечныеПути: Set(исходные.map { Data((карта[Data($0.utf8)] ?? $0).utf8) }))
    }

    @Test("Состав и SHA сверяются до разрешения ссылок")
    func независимыйСостав() throws {
        let ожидаемые = [ожидание("a.md", "a"), ожидание("b.md", "b")]
        for документы in [[документ("a.md", "a"), документ("c.md", "b")], [документ("a.md", "a"), документ("a.md", "a")], [документ("a.md", "изменено"), документ("b.md", "b")]] {
            #expect(throws: (any Error).self) { try план(документы, ожидаемые) }
        }
        #expect(throws: (any Error).self) { try план([документ("e\u{301}.md", "x")], [ожидание("é.md", "x")]) }
    }

    @Test("Неуспешный документ не теряет успешного соседа")
    func отдельныеИсходы() throws {
        let документы = [документ("a.md", "[x](https://example.invalid)"), документ("b.md", "[[missing]]")]
        let результат = try план(документы, [ожидание("a.md", "[x](https://example.invalid)"), ожидание("b.md", "[[missing]]")])
        try #require(результат.документы.count == 2)
        #expect(результат.документы[0].состояние == .провереныПути)
        #expect(результат.документы[1].состояние == .неПроверено)
        #expect(результат.документы[1].первыйОтказ != nil)
        #expect(результат.полнотаУчёта && !результат.полнотаПутейПриПереданныхРолях)
    }

    @Test("Literal и unknown не становятся одним успешным identity")
    func разныеРоли() throws {
        let текст = "[old](missing.md)", документы = [документ("a.md", текст, .дословный), документ("b.md", текст, .неизвестный)]
        let результат = try план(документы, [ожидание("a.md", текст), ожидание("b.md", текст)])
        try #require(результат.документы.count == 2)
        #expect(результат.документы.map(\.состояние) == [.сохраненыБайты, .неПроверено])
        #expect(результат.документы[0].будущиеБайты == Data(текст.utf8))
        #expect(результат.документы[0].целиПосле.isEmpty)
    }

    @Test("Скрытые защитные ветви resolver не дают active proof")
    func конфликтРоли() throws {
        let документы = [документ("Источники/a.md", "[old](missing.md)"), документ("Журнал/old/запрос.md", "старый формат")]
        let результат = try план(документы, [ожидание("Источники/a.md", "[old](missing.md)"), ожидание("Журнал/old/запрос.md", "старый формат")])
        try #require(результат.документы.count == 2)
        #expect(результат.документы.allSatisfy { $0.состояние == .неПроверено })
        #expect(!результат.полнотаПутейПриПереданныхРолях)
    }

    @Test("Оба oldDoc остаются при одном futureDoc и разных целях")
    func участникиОбъединения() throws {
        let текст = "[r](../t.md)", документы = [документ("a/docs/x.md", текст), документ("b/docs/x.md", текст)]
        let ожидаемые = [ожидание("a/docs/x.md", текст), ожидание("b/docs/x.md", текст)]
        let результат = try план(документы, ожидаемые, пары: [("a/docs/x.md", "common/x.md"), ("b/docs/x.md", "common/x.md")], пути: ["a/docs/x.md", "b/docs/x.md", "a/t.md", "b/t.md"])
        try #require(результат.документы.count == 2)
        #expect(результат.документы.map(\.будущийПуть) == ["common/x.md", "common/x.md"])
        #expect(результат.документы[0].будущиеБайты != результат.документы[1].будущиеБайты)
        #expect(!результат.препятствия.isEmpty)
    }

    @Test("Повторы targets и query/fragment сохраняются, перестановка входа стабильна")
    func порядокИСуффиксы() throws {
        let текст = "[a](t.md?q#f) [b](t.md?q#f) [c](a%23b.md) [d](a%3Fb.md)", документы = [документ("x.md", текст), документ("z.md", "z")]
        let ожидаемые = [ожидание("x.md", текст), ожидание("z.md", "z")], пути = ["x.md", "z.md", "t.md", "a#b.md", "a?b.md"]
        let один = try план(документы, ожидаемые, пути: пути), два = try план(документы.reversed(), ожидаемые.reversed(), пути: пути.reversed())
        #expect(один.документы.first?.целиПосле == ["t.md", "t.md", "a#b.md", "a?b.md"])
        #expect(один.документы.first?.будущиеБайты == Data(текст.utf8))
        #expect(!один.якоряИЗапросыПроверены && !один.готовностьКонтекста && !один.применениеРазрешено)
        #expect(try байтыПлана(один) == байтыПлана(два))
    }

    @Test("Защищённый поддиапазон вне Журнала требует отдельного основания")
    func скрытаяЗащитнаяОбласть() throws {
        let текст = "## Текст запроса\n[x](missing.md)\n"
        let результат = try план([документ("a.md", текст)], [ожидание("a.md", текст)])
        #expect(результат.документы.first?.состояние == .неПроверено)
        #expect(!результат.полнотаПутейПриПереданныхРолях)
    }

    @Test("Алиасы компонентов не скрываются за разными конечными именами")
    func префиксныеАлиасы() throws {
        for пути in [["A/x.md", "a/y.md"], ["e\u{301}/x.md", "é/y.md"]] {
            let документы = пути.map { документ($0, "x", .дословный) }, ожидаемые = пути.map { ожидание($0, "x") }
            #expect(throws: (any Error).self) { try план(документы, ожидаемые) }
        }
    }

    @Test("Изменение роли или её основания меняет отдельный отпечаток")
    func привязкаРолей() throws {
        let ожидаемые = [ожидание("a.md", "x")]
        let первый = try план([документ("a.md", "x")], ожидаемые)
        let второй = try план([документ("a.md", "x", .дословный)], ожидаемые)
        var иной = документ("a.md", "x"); иной.основаниеРоли = "другое-проверочное-основание"
        let третий = try план([иной], ожидаемые)
        #expect(первый.хэшРолей != второй.хэшРолей && первый.хэшРолей != третий.хэшРолей)
        #expect(первый.хэшОжидаемогоКорпуса == второй.хэшОжидаемогоКорпуса)
        #expect(!первый.готовностьКонтекста && !второй.готовностьКонтекста && !третий.готовностьКонтекста)
    }
}

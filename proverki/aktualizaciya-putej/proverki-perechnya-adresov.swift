private final class КаталогДиагностическихКвитанций {
    private let родитель: Int32
    private let каталог: Int32
    init(назначение: URL, корень: URL) throws {
        let имя = назначение.lastPathComponent
        guard !["", ".", ".."].contains(имя), !имя.contains("/"), !имя.utf8.contains(0), имя.utf8.count <= 255 else { throw ОтказКорпусаСсылок.условие("неверное-имя-каталога-квитанций") }
        let родитель = open(назначение.deletingLastPathComponent().path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard родитель >= 0 else { throw ОтказКорпусаСсылок.условие("нет-физического-родителя-квитанций") }
        var оставить = false
        defer { if !оставить { close(родитель) } }
        var свойства = stat()
        guard fstat(родитель, &свойства) == 0, свойства.st_uid == geteuid(), свойства.st_mode & 0o022 == 0 else { throw ОтказКорпусаСсылок.условие("чужой-или-доступный-другим-родитель-квитанций") }
        let корневой = open(корень.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard корневой >= 0 else { throw ОтказКорпусаСсылок.условие("нет-физического-корня-ограды") }
        defer { close(корневой) }
        var корневые = stat()
        guard fstat(корневой, &корневые) == 0 else { throw ОтказКорпусаСсылок.условие("нет-identity-корня-ограды") }
        var предок = dup(родитель), дошёл = false
        guard предок >= 0 else { throw ОтказКорпусаСсылок.условие("нет-дескриптора-предка") }
        defer { close(предок) }
        for _ in 0..<256 {
            var текущие = stat()
            guard fstat(предок, &текущие) == 0, текущие.st_dev != корневые.st_dev || текущие.st_ino != корневые.st_ino else { throw ОтказКорпусаСсылок.условие("квитанции-внутри-checkout") }
            let следующий = openat(предок, "..", O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            guard следующий >= 0 else { throw ОтказКорпусаСсылок.условие("не-открыт-физический-предок") }
            var следующие = stat()
            guard fstat(следующий, &следующие) == 0 else { close(следующий); throw ОтказКорпусаСсылок.условие("не-проверен-предок") }
            if текущие.st_dev == следующие.st_dev && текущие.st_ino == следующие.st_ino { close(следующий); дошёл = true; break }
            close(предок); предок = следующий
        }
        guard дошёл, mkdirat(родитель, имя, 0o700) == 0 else { throw ОтказКорпусаСсылок.условие("нет-нового-внешнего-каталога-квитанций") }
        let каталог = openat(родитель, имя, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard каталог >= 0 else { throw ОтказКорпусаСсылок.условие("не-открыт-новый-каталог-квитанций") }
        var созданные = stat(), поИмени = stat()
        guard fstat(каталог, &созданные) == 0, созданные.st_uid == geteuid(), созданные.st_mode & 0o777 == 0o700,
              fstatat(родитель, имя, &поИмени, AT_SYMLINK_NOFOLLOW) == 0, созданные.st_dev == поИмени.st_dev, созданные.st_ino == поИмени.st_ino,
              fsync(родитель) == 0 else { close(каталог); throw ОтказКорпусаСсылок.условие("не-подтверждён-каталог-квитанций") }
        self.родитель = родитель; self.каталог = каталог; оставить = true
    }
    deinit { close(каталог); close(родитель) }
    func записать(_ имя: String, _ байты: Data) throws {
        guard !["", ".", ".."].contains(имя), !имя.contains("/"), !имя.utf8.contains(0), имя.utf8.count <= 255, байты.count <= 33_554_432 else { throw ОтказКорпусаСсылок.условие("неверная-квитанция") }
        let файл = openat(каталог, имя, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        guard файл >= 0 else { throw ОтказКорпусаСсылок.условие("квитанция-уже-существует-или-недоступна") }
        defer { close(файл) }
        try байты.withUnsafeBytes { буфер in
            var записано = 0
            while записано < буфер.count {
                let число = Darwin.write(файл, буфер.baseAddress!.advanced(by: записано), буфер.count - записано)
                if число < 0 && errno == EINTR { continue }
                guard число > 0 else { throw ОтказКорпусаСсылок.условие("неполная-запись-квитанции") }
                записано += число
            }
        }
        guard fsync(файл) == 0, fsync(каталог) == 0 else { throw ОтказКорпусаСсылок.условие("не-подтверждена-запись-квитанции") }
    }
}

@Suite("Полный диагностический перечень Markdown-адресов")
struct ПроверкиПеречняАдресов {
    func документ(_ текст: String, путь: String = "docs/x.md") -> ДокументСсылокПакета {
        let байты = Data(текст.utf8)
        return .init(путь: путь, байты: байты, sha256: хэшПутей(байты))
    }
    @Test("Каждое reference-упоминание и forward definition сохраняются отдельно")
    func повторныеУпоминания() throws {
        let вход = документ("Ёж [one][r] ![two][r] [r][] [r]\r\n[r]: ../a/f?x#p\r\n")
        let итог = РешательСсылокПакета.перечислитьАдреса(вход)
        #expect(итог.обходЗавершён && итог.синтаксисПолностьюРаспознан && итог.хэшПроверен)
        #expect(итог.узлы.count == 5)
        let определение = try #require(итог.узлы.first { $0.вид == .определение })
        let ссылки = итог.узлы.filter { $0.вид != .определение }
        #expect(ссылки.count == 4 && ссылки.allSatisfy { $0.определения == [определение.номер] })
        #expect(ссылки.map(\.вид) == [.полная, .полная, .свёрнутая, .сокращённая])
        #expect(ссылки.map(\.изображение) == [false, true, false, false])
        #expect(итог.узлы.map(\.номер) == Array(0..<5))
        #expect(!итог.ролиПроверены && !итог.разрешениеЦелейПроверено && !итог.применениеРазрешено)
    }

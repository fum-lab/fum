@Suite("Конечный профиль объединения документации")
struct ПроверкиОбъединенияДокументации {
    let индекс = Data("индекс фикстуры".utf8)
    var основа: ОсноваОбщейМиграции {
        .init(корневаяЗадача: "01a07d3d-d376-7ad2-aafc-67e4c25a67eb", владелец: "fixture",
            ветка: "refs/heads/fixture", коммит: String(repeating: "a", count: 40),
            дерево: String(repeating: "b", count: 40), индексSHA256: хэшПутей(индекс))
    }
    func каталог(_ путь: String) -> УзелОбщейМиграции { .init(путь: путь, вид: .каталог, режим: "040000") }
    func файл(_ путь: String, _ текст: String) -> УзелОбщейМиграции {
        .init(путь: путь, вид: .файл, режим: "100644", объект: String(repeating: "d", count: 40), байты: Data(текст.utf8))
    }
    func план(_ файлы: [УзелОбщейМиграции], каноны: [КаноническаяКопияДокументации] = []) throws -> ПланПакетаДокументации {
        let узлы = [каталог("Документация"), каталог("dokumentaciya")] + файлы
        return try ПрофильОбъединенияДокументации.построить(основа: основа, ожидаемаяОснова: основа,
            узлы: узлы, пространство: Set(узлы.map { Data($0.путь.utf8) }),
            индексДо: индекс, каноны: каноны)
    }
    func канон(_ исходный: УзелОбщейМиграции, _ целевой: УзелОбщейМиграции,
        подготовленный: Bool = false) -> КаноническаяКопияДокументации {
        .init(исходный: исходный.путь, целевой: целевой.путь, исходныйSHA256: хэшПутей(исходный.байты),
            целевойSHA256: хэшПутей(целевой.байты), основание: "отдельное решение владельца фикстуры",
            подготовленнаяЦель: подготовленный)
    }

    @Test("Свободная цель планирует настоящий MOVE, сохраняет basename и исполняемый режим")
    func свободнаяЦель() throws {

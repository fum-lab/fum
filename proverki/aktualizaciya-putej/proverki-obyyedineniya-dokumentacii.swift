        #expect(результат.шаги[0].целевой == "dokumentaciya/Keep-FUM.bin")
        #expect(результат.шаги[0].после.last?.режим == "100755")
        #expect(результат.отображения.contains { $0.исходный == исходный.путь && $0.целевой == "dokumentaciya/Keep-FUM.bin" })
    }


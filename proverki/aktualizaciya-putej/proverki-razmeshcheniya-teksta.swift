@Suite("Размещение дословных байтов не выводится из заголовков")
struct ПроверкиРазмещенияТекста {
    let политика = Data("Условный вход для проверки байтов; допуск ROOT этим не создаётся.\n".utf8)
    let корпус = String(repeating: "a", count: 64)
    let путь = "Журнал/fixture/запрос.md"
    func фикстура() -> (Data, ПланРазмещенияТекста, [ИсточникДословныхБайтов]) {
        let до = Data("[служебная](old.md)\r\n".utf8), ввод = Data("## Текст запроса\r\n## Идентификатор сеанса Codex\r\ne\u{301} и ё\r\n".utf8), между = Data("между\n".utf8), после = Data("после\n".utf8)
        let второй = до.count + ввод.count + между.count
        let документ = до + ввод + между + ввод + после
        let диапазоны: [ДиапазонРолиТекста] = [.init(начало: 0, длина: до.count, роль: .служебный), .init(начало: до.count, длина: ввод.count, роль: .дословный),
            .init(начало: до.count + ввод.count, длина: между.count, роль: .служебный), .init(начало: второй, длина: ввод.count, роль: .дословный), .init(начало: второй + ввод.count, длина: после.count, роль: .служебный)]
        let копии = [до.count, второй].map { КопияДословногоТекста(источник: "буфер-1", хэшИсточника: хэшПутей(ввод), началоИсточника: 0, началоДокумента: $0, длина: ввод.count, хэшКопии: хэшПутей(ввод)) }
        return (документ, .init(путь: путь, хэшДокумента: хэшПутей(документ), размерДокумента: документ.count, хэшКорпуса: корпус, хэшПолитики: хэшПутей(политика), диапазоны: диапазоны, копии: копии),
            [.init(имя: "буфер-1", байты: ввод, ожидаемыйХэш: хэшПутей(ввод), происхождение: "синтетический исходный буфер; не человеческая цитата")])
    }
    func проверить(_ документ: Data, _ модель: ПланРазмещенияТекста, _ источники: [ИсточникДословныхБайтов]) throws -> ПроверенноеРазмещениеТекста {
        let план = try байтыПлана(модель)
        return try ПроверкаРазмещенияТекста.проверить(путь: путь, документ: документ, план: план, ожидаемыйХэшПлана: хэшПутей(план),
            хэшКорпуса: корпус, политика: политика, ожидаемыйХэшПолитики: хэшПутей(политика), источники: источники)
    }
    @Test("Повторные fake H2 и UTF-8/CRLF сохраняются отдельными исходными размещениями")
    func повторныеРазмещения() throws {
        let (документ, модель, источники) = фикстура(), итог = try проверить(документ, модель, источники)
        #expect(итог.копии.count == 2 && итог.копии[0].началоДокумента != итог.копии[1].началоДокумента)
        #expect(итог.диапазоны == модель.диапазоны && итог.хэшДокумента == хэшПутей(документ))
        #expect(!итог.допускРолейПроверен && !итог.применениеРазрешено)
        let срез = (Data([0, 0]) + документ).dropFirst(2)
        #expect(try проверить(срез, модель, источники).хэшПлана == итог.хэшПлана)
        var срезИсточника = источники; срезИсточника[0].байты = (Data([0, 0]) + источники[0].байты).dropFirst(2)
        #expect(try проверить(документ, модель, срезИсточника).хэшИсточников == итог.хэшИсточников)
        var несколько = модель
        let первая = модель.копии[0], исходный = Data(источники[0].байты)
        let левая = КопияДословногоТекста(источник: первая.источник, хэшИсточника: первая.хэшИсточника, началоИсточника: 0,
            началоДокумента: первая.началоДокумента, длина: 2, хэшКопии: хэшПутей(исходный.subdata(in: 0..<2)))
        let правая = КопияДословногоТекста(источник: первая.источник, хэшИсточника: первая.хэшИсточника, началоИсточника: 2,
            началоДокумента: первая.началоДокумента + 2, длина: первая.длина - 2, хэшКопии: хэшПутей(исходный.subdata(in: 2..<исходный.count)))
        несколько.копии = [левая, правая, модель.копии[1]]
        #expect(try проверить(документ, несколько, источники).копии.count == 3)
    }
    @Test("Неполное покрытие, перекрытие и недоказанная literal-копия закрываются")
    func неверныеРазмещения() throws {
        let (документ, исходная, источники) = фикстура()
        for вариант in 0..<6 {
            var модель = исходная
            switch вариант {
            case 0: модель.диапазоны[1].начало += 1
            case 1: модель.диапазоны[1].начало -= 1
            case 2: модель.копии.removeLast()
            case 3: модель.копии[0].началоИсточника = Int.max
            case 4: модель.копии[0].началоДокумента = 0
            default: модель.копии[0].хэшКопии = String(repeating: "0", count: 64)
            }
            #expect(throws: (any Error).self) { try проверить(документ, модель, источники) }
        }
    }
    @Test("Drift документа/источника/плана/политики и разрыв UTF-8 закрываются")
    func привязкиИГраницы() throws {
        let (документ, модель, источники) = фикстура()
        #expect(throws: (any Error).self) { try проверить(документ + Data([10]), модель, источники) }
        var изменённые = источники; изменённые[0].байты.append(10)
        #expect(throws: (any Error).self) { try проверить(документ, модель, изменённые) }
        изменённые = источники
        var неверныеБайты = Array(изменённые[0].байты); неверныеБайты[0] = 120
        изменённые[0].байты = Data(неверныеБайты); изменённые[0].ожидаемыйХэш = хэшПутей(изменённые[0].байты)
        var согласованныеХэши = модель
        for номер in согласованныеХэши.копии.indices { согласованныеХэши.копии[номер].хэшИсточника = изменённые[0].ожидаемыйХэш }
        #expect(throws: (any Error).self) { try проверить(документ, согласованныеХэши, изменённые) }
        let план = try байтыПлана(модель)
        #expect(throws: (any Error).self) {
            try ПроверкаРазмещенияТекста.проверить(путь: путь, документ: документ, план: план, ожидаемыйХэшПлана: String(repeating: "0", count: 64),
                хэшКорпуса: корпус, политика: политика, ожидаемыйХэшПолитики: хэшПутей(политика), источники: источники)
        }
        #expect(throws: (any Error).self) {
            try ПроверкаРазмещенияТекста.проверить(путь: путь, документ: документ, план: план, ожидаемыйХэшПлана: хэшПутей(план),
                хэшКорпуса: корпус, политика: политика + Data([10]), ожидаемыйХэшПолитики: хэшПутей(политика), источники: источники)
        }
        let ё = Data("ё".utf8)
        var разрыв = модель; разрыв.хэшДокумента = хэшПутей(ё); разрыв.размерДокумента = ё.count; разрыв.копии = []
        разрыв.диапазоны = [.init(начало: 0, длина: 1, роль: .служебный), .init(начало: 1, длина: 1, роль: .служебный)]
        #expect(throws: (any Error).self) { try проверить(ё, разрыв, []) }
    }

    @Test("Происхождение входит в хэш; повторный источник и поддельные поля закрываются")
    func происхождениеИЗакрытость() throws {
        let (документ, модель, источники) = фикстура()
        let прежде = try проверить(документ, модель, источники)
        var иначе = источники; иначе[0].происхождение = "иная заявленная опора; не доказательство роли человека"
        #expect(try проверить(документ, модель, иначе).хэшИсточников != прежде.хэшИсточников)
        #expect(throws: (any Error).self) { try проверить(документ, модель, источники + источники) }
        var объект = try #require(JSONSerialization.jsonObject(with: байтыПлана(модель)) as? [String: Any])
        объект["применениеРазрешено"] = true
        let подделка = try JSONSerialization.data(withJSONObject: объект)
        #expect(throws: (any Error).self) {
            try ПроверкаРазмещенияТекста.проверить(путь: путь, документ: документ, план: подделка, ожидаемыйХэшПлана: хэшПутей(подделка),
                хэшКорпуса: корпус, политика: политика, ожидаемыйХэшПолитики: хэшПутей(политика), источники: источники)
        }
    }

    @Test("Адресный собственный запрос связывается с входом строителя, а не с H2",
          .enabled(if: ProcessInfo.processInfo.environment["ФУМ_ДОКУМЕНТ_РАЗМЕЩЕНИЯ"] != nil))
    func адресныйЗапрос() throws {
        let среда = ProcessInfo.processInfo.environment
        let адресДокумента = try #require(среда["ФУМ_ДОКУМЕНТ_РАЗМЕЩЕНИЯ"]), адресВхода = try #require(среда["ФУМ_ВХОД_ЖУРНАЛА_РАЗМЕЩЕНИЯ"])
        let логическийПуть = try #require(среда["ФУМ_ЛОГИЧЕСКИЙ_ПУТЬ_РАЗМЕЩЕНИЯ"]), хэшДокумента = try #require(среда["ФУМ_ХЭШ_ДОКУМЕНТА_РАЗМЕЩЕНИЯ"])
        let хэшВхода = try #require(среда["ФУМ_ХЭШ_ВХОДА_РАЗМЕЩЕНИЯ"]), хэшКорпуса = try #require(среда["ФУМ_ХЭШ_КОРПУСА_РАЗМЕЩЕНИЯ"])
        let документ = try ограниченно(адресДокумента, предел: 33_554_432), вход = try ограниченно(адресВхода, предел: 4_194_304)
        try #require(хэшПутей(документ) == хэшДокумента && хэшПутей(вход) == хэшВхода)
        _ = try ТокеныJSONМиграции.разобрать(вход)
        let объект = try #require(JSONSerialization.jsonObject(with: вход) as? [String: Any]), текст = try #require(объект["текст"] as? String)
        let исходный = Data(текст.utf8), найденный = try #require(документ.range(of: исходный))
        try #require(документ.range(of: исходный, in: найденный.upperBound..<документ.count) == nil)
        let хэшИсходного = хэшПутей(исходный)
        let опора = ИсточникДословныхБайтов(имя: "декодированный-текст-строителя", байты: исходный, ожидаемыйХэш: хэшИсходного,
            происхождение: "Производный UTF-8 буфер /текст из JSON SHA256=" + хэшВхода + "; не доказательство нативного человеческого происхождения")
        let условнаяПолитика = try JSONSerialization.data(withJSONObject: ["схема": "fum.условная-опора-размещения.1", "источник": хэшВхода, "допускРолейПроверен": false], options: [.prettyPrinted, .sortedKeys]) + Data([10])
        var части: [ДиапазонРолиТекста] = []
        if найденный.lowerBound > 0 { части.append(.init(начало: 0, длина: найденный.lowerBound, роль: .служебный)) }
        части.append(.init(начало: найденный.lowerBound, длина: найденный.count, роль: .дословный))
        if найденный.upperBound < документ.count { части.append(.init(начало: найденный.upperBound, длина: документ.count - найденный.upperBound, роль: .служебный)) }
        let модель = ПланРазмещенияТекста(путь: логическийПуть, хэшДокумента: хэшДокумента, размерДокумента: документ.count, хэшКорпуса: хэшКорпуса,
            хэшПолитики: хэшПутей(условнаяПолитика), диапазоны: части,
            копии: [.init(источник: опора.имя, хэшИсточника: хэшИсходного, началоИсточника: 0, началоДокумента: найденный.lowerBound, длина: найденный.count, хэшКопии: хэшИсходного)])
        let план = try байтыПлана(модель)
        let результат = try ПроверкаРазмещенияТекста.проверить(путь: логическийПуть, документ: документ, план: план, ожидаемыйХэшПлана: хэшПутей(план),
            хэшКорпуса: хэшКорпуса, политика: условнаяПолитика, ожидаемыйХэшПолитики: хэшПутей(условнаяПолитика), источники: [опора])
        #expect(результат.копии.count == 1 && результат.размещениеБайтовПроверено && !результат.допускРолейПроверен && !результат.применениеРазрешено)
        #expect(try хэшПутей(ограниченно(адресДокумента, предел: 33_554_432)) == хэшДокумента)
        if let выход = среда["ФУМ_РЕЗУЛЬТАТ_РАЗМЕЩЕНИЯ"] {
            let квитанция: [String: Any] = ["схема": "fum.адресная-проверка-размещения.1", "хэшДокумента": хэшДокумента, "хэшВходаСтроителя": хэшВхода,
                "хэшПлана": результат.хэшПлана, "хэшИсточников": результат.хэшИсточников, "хэшПолитики": результат.хэшПолитики, "начало": найденный.lowerBound,
                "длина": найденный.count, "размещениеБайтовПроверено": true, "допускРолейПроверен": false, "применениеРазрешено": false]
            let байты = try JSONSerialization.data(withJSONObject: квитанция, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) + Data([10])
            try байты.write(to: URL(fileURLWithPath: выход), options: .withoutOverwriting)
        }
    }

    func ограниченно(_ путь: String, предел: Int) throws -> Data {
        let файл = try FileHandle(forReadingFrom: URL(fileURLWithPath: путь)); defer { try? файл.close() }
        var данные = Data()
        while let часть = try файл.read(upToCount: 1_048_576), !часть.isEmpty {
            try #require(часть.count <= предел - данные.count)
            данные.append(часть)
        }
        return данные
    }

import Foundation
import Testing

@Suite("Команда чтения одного имени")
struct ПроверкиКомандыОдногоИмени {
    @Test("Неверная форма отклоняется до чтения снимка")
    func неверныеАргументы() async {
        for аргументы in [["имя"], ["имя", "ОтветыКоординатору"], ["имя", "--компонент", "ОтветыКоординатору", "лишнее"]] {
            await #expect(throws: (any Error).self) { try await КомандаПутей.выполнить(аргументы) }
        }
    }

    @Test("Служебные имена и косая черта отклоняются Names-фасадом")
    func запрещённыеКомпоненты() async {
        for компонент in ["Package.swift", "AGENTS.md", "a/b"] {
            await #expect(throws: (any Error).self) {
                try await КомандаПутей.выполнить(["имя", "--компонент", компонент])
            }
        }
    }

    @Test("JSON совпадает с публичным Names-вызовом и сохраняет происхождение")
    func точноеДелегирование() async throws {
        let компонент = "ОтветыКоординатору"
        let данные = try await КомандаПутей.выполнить(["имя", "--компонент", компонент])
        let результат = try JSONDecoder().decode(ПубличноеИмя.self, from: данные)
        let ожидаемый = try await ПубличныйФасадИмён.канонизировать(компонент)
        #expect(результат == ожидаемый)
        #expect(результат.происхождение.коммит == "c6af44bf1ec061675b6205b9c6ee889d98264f28")
        #expect(результат.происхождение.ревизияЗависимости == "837e2ce107b97ee7b9d3344c9fe99142281fe393")
    }
}

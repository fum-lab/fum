                            сырыеБайтыОтвета: запись.сырыеБайтыОтвета, сырыеБайтыНаблюдения: байты)
        return .init(байты: байты, sha256: хэшПутей(байты))
    }
    func добавитьИсход(строка: Data, дляПопытки id: String) async throws -> СнимокСырогоЖурналаАдресаАгента {
        let исходная = try JSONDecoder().decode(ЗаписьЖурналаПопыткиАдресаАгента.self, from: строка)
        guard let запись = попытки[id], запись.намерение == исходная.намерение,
              запись.командаSHA256 == исходная.командаSHA256 else { throw ОшибкаФикстурыАдреса.потерянОтвет }
        попытки[id] = .init(намерение: запись.намерение, командаSHA256: запись.командаSHA256,
                            квитанцияSHA256: исходная.квитанцияSHA256, исход: исходная.исход,
                            сырыеБайтыОтвета: запись.сырыеБайтыОтвета,
                            сырыеБайтыНаблюдения: запись.сырыеБайтыНаблюдения)
        журнал.append(строка)
        return .init(байты: журнал, границаПолна: полнота)
    }
    func прочитатьПопытку(_ id: String) async throws -> СохранённаяПопыткаАдресаАгента? { попытки[id] }
    func сырыеБайтыЖурнала() -> Data { журнал }

    private let дрейфПослеПотребления: Bool
    private var потреблено = false
    private var дрейфДобавлен = false
    private var попытки: [String: СохранённаяПопыткаАдресаАгента] = [:]

    init(журнал: Data = Data(), полнота: ФактАдресаАгента = .да, дрейфПослеПотребления: Bool = false) {
        self.журнал = журнал; self.полнота = полнота; self.дрейфПослеПотребления = дрейфПослеПотребления
    }
    func прочитатьЖурнал() async throws -> СнимокСырогоЖурналаАдресаАгента {
        if дрейфПослеПотребления && потреблено && !дрейфДобавлен {
            журнал.append(10); дрейфДобавлен = true
        }
        return .init(байты: журнал, границаПолна: полнота)
    }
    func потребитьПопытку(строка: Data, ожидаемыйЖурналSHA256: String) async throws
        -> СнимокСырогоЖурналаАдресаАгента {
        guard полнота == .да, хэшПутей(журнал) == ожидаемыйЖурналSHA256,
              !строка.isEmpty, строка.last == 10 else { throw ОшибкаФикстурыАдреса.потерянОтвет }
        let запись = try JSONDecoder().decode(ЗаписьЖурналаПопыткиАдресаАгента.self, from: строка)
        let id = запись.намерение.идентификатор
        guard попытки[id] == nil else { throw ОшибкаФикстурыАдреса.потерянОтвет }
        попытки[id] = .init(намерение: запись.намерение, командаSHA256: запись.командаSHA256,
                            квитанцияSHA256: nil, исход: nil, сырыеБайтыОтвета: nil, сырыеБайтыНаблюдения: nil)
        журнал.append(строка); потреблено = true
        return .init(байты: журнал, границаПолна: полнота)
    }
    func сохранитьСыройОтвет(_ байты: Data, дляПопытки id: String) async throws -> СохранённыйСыройАртефактАдресаАгента {
        guard let запись = попытки[id] else { throw ОшибкаФикстурыАдреса.потерянОтвет }
        попытки[id] = .init(намерение: запись.намерение, командаSHA256: запись.командаSHA256,
                            квитанцияSHA256: хэшПутей(байты), исход: запись.исход,
                            сырыеБайтыОтвета: байты, сырыеБайтыНаблюдения: запись.сырыеБайтыНаблюдения)
        return .init(байты: байты, sha256: хэшПутей(байты))
    }
    func сохранитьСыроеНаблюдение(_ байты: Data, дляПопытки id: String) async throws -> СохранённыйСыройАртефактАдресаАгента {
        guard let запись = попытки[id] else { throw ОшибкаФикстурыАдреса.потерянОтвет }
        попытки[id] = .init(намерение: запись.намерение, командаSHA256: запись.командаSHA256,

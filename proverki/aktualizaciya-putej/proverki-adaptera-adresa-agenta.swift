    )
    return .init(адаптер: адаптер, хранилище: хранилище, транспорт: транспорт)
}

@Suite("Адаптер адреса агента: unsupported create-child boundary")
struct ПроверкиАдаптераАдресаАгента {
    @Test("Create-child остаётся UNKNOWN до intent и не вызывает transport")
    func созданиеРебёнкаНеПоддержаноДоНамерения() async throws {
        let фикстура = ФикстураАдресаАгента()
        let состояние = фикстура.состояние(маршрут: .отказ)
        let план = try состояние.построитьПлан()
        let сыроеНаблюдение = try фикстура.наблюдениеПервогоХода(для: план)
        let сборка = собратьАдаптерФикстуры(
            фикстура, состояния: [состояние], режимПина: .точноеИсключение,
            сыроеНаблюдение: сыроеНаблюдение
        )

        let результат = await сборка.адаптер.выполнить(
            команду: фикстура.команда,
            идентификаторПопытки: попыткаФикстурыАдреса
        )
        let вызовы = await сборка.транспорт.количествоВызовов()
        let журнал = await сборка.хранилище.сырыеБайтыЖурнала()
        #expect(результат.состояние == .неизвестно)
        #expect(результат.причина == "создание-дочерней-сессии-без-принятого-контракта-передачи-владения")
        #expect(вызовы == 0)
        #expect(журнал.isEmpty)
    }

    @Test("Внешний child ID не согласуется с вложенной parent session; точная existing identity согласуется")

private actor СчитывательАдресаФикстуры: СчитывательСостоянияАдресаАгента {
    private let значения: [НаблюдениеРабочегоСостоянияАдресаАгента]
    private var индекс = 0
    init(_ значения: [НаблюдениеРабочегоСостоянияАдресаАгента]) { self.значения = значения }
    func считать() async throws -> НаблюдениеРабочегоСостоянияАдресаАгента {
        guard let последнее = значения.last else { throw ОшибкаФикстурыАдреса.потерянОтвет }
        defer { индекс += 1 }
        return индекс < значения.count ? значения[индекс] : последнее
    }
}


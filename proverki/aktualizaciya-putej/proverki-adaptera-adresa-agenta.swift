    историяSHA256: String,
    маршрут: НаблюдениеМаршрутаАдресаАгента,
    режим: РежимПинаФикстуры,
    путь: String = "fixture/root-permit.json"
) throws -> НезависимыйПинДопускаАдресаАгента {
    // Самохэширование здесь только для синтетической unit-фикстуры, не как доверие ROOT.
    let authoritySHA = String(repeating: "f", count: 64)
    let опоры = try ЯдроАдресаАгента.опоры(
        план: план, источникПолномочия: "mock-root-evidence", полномочиеSHA256: authoritySHA
    )
    let исключение: ИсключениеROOTАдресаАгента?
    switch режим {
    case .безИсключения:
        исключение = nil
    case .точноеИсключение, .невернаяПричинаИсключения:
        исключение = .init(
            корневаяЗадача: опоры.корневаяЗадача,
            причинаОтказа: режим == .точноеИсключение ? маршрут.причина : "different-refusal",
            квитанцияОтказаSHA256: маршрут.квитанцияSHA256,
            опорыSHA256: хэшПутей(try байтыПлана(опоры)),
            планSHA256: план.отпечаток,
            командаSHA256: командаSHA256
        )
    }
    let permit = ДопускЭффектаАдресаАгента(
        опоры: опоры, планSHA256: план.отпечаток, командаSHA256: командаSHA256,
        историяSHA256: историяSHA256, выданоСекундUTC: 100, истекаетСекундUTC: 200,
        маршрут: маршрут.состояние, причинаМаршрута: маршрут.причина,
        квитанцияМаршрутаSHA256: маршрут.квитанцияSHA256, исключениеROOT: исключение
    )
    let bytes = try байтыПлана(permit)
    return .init(
        байты: bytes, утверждённыйSHA256: хэшПутей(bytes),
        авторитет: маршрут.состояние == .пройден ? .проверяющий : .корень,

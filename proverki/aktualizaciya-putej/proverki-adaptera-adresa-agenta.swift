private final class ПоследовательныеЧасыАдресаФикстуры: @unchecked Sendable, ЧасыАдресаАгента {
    private let блокировка = NSLock()
    private var значения: [Int64]
    init(_ значения: [Int64]) { self.значения = значения }
    func сейчасСекундUTC() -> Int64 {
        блокировка.lock(); defer { блокировка.unlock() }
        if значения.count > 1 { return значения.removeFirst() }
        return значения.first ?? 0
    }
}


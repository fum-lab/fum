    func выполнить(_ данные: Data) throws -> КвитанцияНаблюденияГруппы {
        #if ФУМ_ЗАПУСК_ПРОВЕРОК_НАБЛЮДАТЕЛЯ
        let запрос = try JSONDecoder().decode(ЗапросНаблюденияГруппы.self, from: данные)
        guard запрос.каталогИсходов == исходы.path && запрос.рабочийКаталог == корень.path else {
            throw ОшибкаНаблюденияГруппы.отказ("запрос-не-соответствует-фикстуре")
        }
        try БюджетСохраненияНаблюдателя.общий.выделить(дляФикстуры: false, предел: контекст.пределПакетаБайт)
        let номер = UUID().uuidString
        let захват = try захваты.дочерний("вызов-" + номер, вне: контекст.корень)
        последнийВызов = захват; номерВызова += 1
        try захват.записать("запрос.bin", данные)
        try захват.записать("контекст.json", байтыКонтекста)
        try захват.записать("расположение.json", закодироватьСохранение([
            "фикстура": try каталогФикстуры.расположение(), "исходы": try каталогИсходов.расположение(),
            "захват": try захват.расположение()]))
        let (до, полныйДо) = try снимок(захват, префикс: "до-")
        guard полныйДо else { throw ОшибкаНаблюденияГруппы.отказ("неполное-сохранение-до-эффекта") }
        try захват.записать("готовность.json", закодироватьСохранение(["вызов": номер,
            "номер": String(номерВызова), "случай": запрос.аргументы.last ?? "UNKNOWN",
            "поколениеЗапроса": запрос.поколение, "байтЗапроса": String(данные.count),
            "хэшЗапроса": НаблюдательГруппыПроцессов.хэш(данные),
            "хэшКонтекста": НаблюдательГруппыПроцессов.хэш(байтыКонтекста),
            "резервБайт": "524288", "наносекунды": String(DispatchTime.now().uptimeNanoseconds)]))
        let результат = Result { try НаблюдательГруппыПроцессов.выполнить(данные) }
        // Захват выполняется до старых assertions и до повторного броска исходной ошибки.
        do {
            let (после, полныйПосле) = try снимок(захват, префикс: "после-", предыдущий: до)
            let квитанция = после.first { $0["имя"] == "result.json" }
            let квитанцияДоступна = квитанция?["статус"] == "сохранён"
            var исход = ["вызов": номер, "хэшЗапроса": НаблюдательГруппыПроцессов.хэш(данные),
                "захват": полныйПосле && квитанцияДоступна ? "сохранён" : "UNKNOWN",
                "происхождениеКвитанции": квитанция?["происхождение"] ?? "UNKNOWN",
                "наносекунды": String(DispatchTime.now().uptimeNanoseconds)]
            switch результат {
            case .success(let квитанция):
                try захват.записать("возврат.json", закодироватьСохранение(квитанция))
                исход["исходНаблюдателя"] = "возврат"; исход["статусНаблюдателя"] = квитанция.статус
                if !полныйПосле || !квитанцияДоступна { Issue.record("Неполный захват после return наблюдателя") }
            case .failure(let ошибка):
                исход["исходНаблюдателя"] = "ошибка"; исход["ошибкаНаблюдателя"] = String(String(describing: ошибка).prefix(2_048))
            }
            try захват.записать("исход.json", закодироватьСохранение(исход))
        } catch {
            let описание = String(String(describing: error).prefix(2_048))
            try? захват.записать("сбой-сохранения.json", закодироватьСохранение(["вызов": номер,
                "захват": "UNKNOWN", "ошибка": описание]))
            Issue.record("Ошибка сохранения квитанций: \(описание)")
        }
        return try результат.get()
        #else
        throw ОшибкаНаблюденияГруппы.отказ("нужен-проверочный-профиль-хранения")
        #endif
    }
    func сохранитьСуществующуюПроверкуГруппы(_ группа: Int32, код: Int32, ошибка: Int32, наносекунды: UInt64) throws {
        #if ФУМ_ЗАПУСК_ПРОВЕРОК_НАБЛЮДАТЕЛЯ
        guard let захват = последнийВызов else { throw ОшибкаНаблюденияГруппы.отказ("нет-сохранённого-вызова") }
        try захват.записать("прежняя-проверка-группы.json", закодироватьСохранение(["группа": Int64(группа), "код": Int64(код),
            "ошибка": Int64(ошибка), "наносекунды": Int64(наносекунды)]))
        #else
        throw ОшибкаНаблюденияГруппы.отказ("нужен-проверочный-профиль-хранения")
        #endif
    }
    func сохранитьНезавершённоеНамерение(_ данные: Data) throws {
        #if ФУМ_ЗАПУСК_ПРОВЕРОК_НАБЛЮДАТЕЛЯ
        try каталогИсходов.записать("attempt.json", данные)
        #else
        throw ОшибкаНаблюденияГруппы.отказ("нужен-проверочный-профиль-хранения")
        #endif
    }
}


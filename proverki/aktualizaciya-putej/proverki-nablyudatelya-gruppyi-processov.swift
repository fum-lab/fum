private final class БюджетСохраненияНаблюдателя: @unchecked Sendable {
    static let общий = БюджетСохраненияНаблюдателя()
    private let замок = NSLock()
    private var фикстур = 0, вызовов = 0, зарезервировано = 0
    // Включает request/context/index/outcome, два raw-снимка и native run-файлы.
    // Индивидуальные caps в адаптере дают < 512 КиБ на один вызов, включая reserve failure/kill0.
    func выделить(дляФикстуры: Bool, предел: Int) throws {
        замок.lock(); defer { замок.unlock() }
        #if ФУМ_ДИАГНОСТИКА_ПОТОМКОВ_НАБЛЮДАТЕЛЯ
        let максимумФикстур = 1, максимумВызовов = 1, ожидаемыйПредел = 1_048_576
        #else
        let максимумФикстур = 9, максимумВызовов = 10, ожидаемыйПредел = 8_388_608
        #endif
        guard предел == ожидаемыйПредел else { throw ОшибкаНаблюденияГруппы.отказ("не-совпал-предел-пакета-квитанций") }
        if дляФикстуры {
            guard фикстур < максимумФикстур else { throw ОшибкаНаблюденияГруппы.отказ("превышен-предел-фикстур") }
            фикстур += 1
        } else {
            guard вызовов < максимумВызовов, зарезервировано <= предел - 524_288 else {
                throw ОшибкаНаблюденияГруппы.отказ("превышен-предел-вызовов")
            }
            вызовов += 1; зарезервировано += 524_288
        }
    }
}

private func закодироватьСохранение<T: Encodable>(_ значение: T) throws -> Data {
    let кодер = JSONEncoder()
    кодер.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
    return try кодер.encode(значение) + Data([10])
}


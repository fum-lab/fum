              [контекст.компилятор.sha256, контекст.комплектРазработчика.sha256].allSatisfy({ $0.count == 64 }) else {
            throw ОшибкаНаблюденияГруппы.отказ("не-совпал-пин-контекста")
        }
        for пин in контекст.исходники {
            guard НаблюдательГруппыПроцессов.хэш(try Хранилище.прочитатьАртефакт(пин.путь, предел: 8_388_608)) == пин.sha256 else {
                throw ОшибкаНаблюденияГруппы.отказ("не-совпал-пин-исходника")
            }
        }
        let основание = try Хранилище(база, вне: корень)

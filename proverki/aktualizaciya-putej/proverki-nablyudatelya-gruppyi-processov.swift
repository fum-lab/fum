    init() throws {
        #if ФУМ_ЗАПУСК_ПРОВЕРОК_НАБЛЮДАТЕЛЯ
        let среда = ProcessInfo.processInfo.environment
        guard let база = среда["ФУМ_БАЗА_КВИТАНЦИЙ_НАБЛЮДАТЕЛЯ"],
              let корень = среда["ФУМ_КОРЕНЬ_ПРОВЕРКИ_НАБЛЮДАТЕЛЯ"],

    #if ФУМ_ЗАПУСК_ПРОВЕРОК_НАБЛЮДАТЕЛЯ
    private func снимок(_ захват: Хранилище, префикс: String,
                        предыдущий: [[String: String]] = []) throws -> ([[String: String]], Bool) {
        _ = try каталогИсходов.расположение()
        var записи: [[String: String]] = [], полный = true, вывода = 0
        for (имя, копия, предел) in [("attempt.json", "намерение.bin", 4_096), ("spawn.json", "запуск.bin", 4_096),
            ("result.json", "квитанция.bin", 16_384), ("stdout.bin", "стандартный-вывод.bin", 65_536),
            ("stderr.bin", "поток-ошибок.bin", 65_536)] {
            let путь = исходы.path + "/" + имя
            var свойства = stat(), запись = ["имя": имя]
            errno = 0
            let код = lstat(путь, &свойства), ошибка = errno
            if код == -1 && ошибка == ENOENT { запись["статус"] = "отсутствует" }
            else {
                do {
                    guard код == 0, свойства.st_mode & 0o777 == 0o600 else {
                        throw ОшибкаНаблюденияГруппы.отказ("не-проверен-исходный-файл-\(ошибка)")
                    }
                    let данные = try Хранилище.прочитатьАртефакт(путь, предел: предел)
                    if имя == "stdout.bin" || имя == "stderr.bin" {
                        вывода += данные.count
                        guard вывода <= 65_536 else { throw ОшибкаНаблюденияГруппы.отказ("превышен-совместный-предел-вывода") }
                    }
                    try захват.записать(префикс + копия, данные)
                    запись.merge(["статус": "сохранён", "байт": String(данные.count),
                        "хэш": НаблюдательГруппыПроцессов.хэш(данные), "устройство": String(свойства.st_dev),
                        "узел": String(свойства.st_ino), "пользователь": String(свойства.st_uid),
                        "режим": String(свойства.st_mode & 0o777)]) { _, новое in новое }
                    let старый = предыдущий.first { $0["имя"] == имя }
                    запись["происхождение"] = старый?["хэш"] == запись["хэш"]
                        && старый?["устройство"] == запись["устройство"] && старый?["узел"] == запись["узел"]
                        ? "существовал-до-вызова" : "появился-или-изменился"
                } catch {
                    запись["статус"] = "UNKNOWN"; запись["ошибка"] = String(String(describing: error).prefix(512)); полный = false
                }
            }
            записи.append(запись)
        }
        try захват.записать(префикс + "перечень.json", закодироватьСохранение(записи))
        return (записи, полный)
    }

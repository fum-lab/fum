@Suite("Мост точного Git-пространства к условным адресам")
struct ПроверкиПереходаПространства {
    let корень = КорневоеОтображениеМиграции(исходный: "Инструменты", целевой: "instrumentyi", источникИмени: "fixture")
    func пространство(_ записи: [(String, String)]) throws -> ПроверенноеПространствоИмёнGit {
        let листья = записи.map { путь, режим in
            ЛистДереваGit(путь: Data(путь.utf8), режим: режим, объект: String(repeating: "1", count: 40),
                вид: режим == "160000" ? .внешняяЗависимость : режим == "120000" ? .символическаяСсылка : .файл)
        }
        let дерево = try ПространствоИмёнGit.вычислитьДерево(листья)
        let сырые = Data(листья.map { "\($0.режим) \($0.вид == .внешняяЗависимость ? "commit" : "blob") \($0.объект)\t\(String(decoding: $0.путь, as: UTF8.self))\0" }.joined().utf8)
        let индекс = Data(листья.map { "\($0.режим) \($0.объект) 0\t\(String(decoding: $0.путь, as: UTF8.self))\0" }.joined().utf8)
        return try ПространствоИмёнGit.проверить(переченьДерева: сырые, индекс: индекс, ожидаемоеДерево: дерево, ожидаемыйХэшИндекса: хэшПутей(индекс))
    }
    func мост(_ вход: ПроверенноеПространствоИмёнGit) throws -> ПроектПространстваАдресов {
        try ПереходПространстваАдресов.построить(вход, ожидаемоеДерево: вход.дерево, ожидаемыйХэшИндекса: вход.хэшИндекса,
            ожидаемыйХэшПеречня: вход.хэшСырогоПеречня, корень: корень, исключитьПроекцию: true)
    }
    @Test("Точный корень и Proyekcii отделяются от соседей, raw suffix сохраняется")
    func точныеПрефиксы() throws {
        let хвост = "/e\u{301}/\u{301}x.md", вход = try пространство([
            ("Инструменты" + хвост, "100644"), ("Инструменты-old/f", "100644"),
            ("Proyekcii/f", "100644"), ("Proyekcii-old/f", "100644"), ("nested/Proyekcii/f", "100644")])
        let р = try мост(вход), к = try #require(р.контекст)
        #expect(к.исходные[Data(("Инструменты" + хвост).utf8)] == .файл)
        #expect(к.будущие[Data(("instrumentyi" + хвост).utf8)] == .файл)
        #expect(к.будущие[Data("Инструменты-old/f".utf8)] == .файл && к.будущие[Data("Proyekcii-old/f".utf8)] == .файл)
        #expect(к.будущие[Data("nested/Proyekcii/f".utf8)] == .файл && к.будущие[Data("Proyekcii/f".utf8)] == nil)
        #expect(р.удаляемыеЛистья == [Data("Proyekcii/f".utf8)] && р.препятствия.isEmpty)
        #expect(!р.применениеРазрешено && !р.содержимоеОбъектовПроверено && !р.файловаяСистемаПроверена && !р.имяКорняПроверено && !р.собственныеВходыВключены)
    }
    @Test("Непересекающиеся назначения объединяют каталоги и сохраняют все строки")
    func объединениеКаталогов() throws {
        let р = try мост(пространство([("Инструменты/A/f", "100644"), ("instrumentyi/A/g", "100644")]))
        let к = try #require(р.контекст)
        #expect(к.будущие[Data("instrumentyi/A/f".utf8)] == .файл && к.будущие[Data("instrumentyi/A/g".utf8)] == .файл)
        #expect(р.отображения.count == 6)
        #expect(р.группы.contains { $0.целевой == "instrumentyi/A" && $0.исходные.count == 2 && $0.вид == .объединениеКаталогов })
        #expect(р.деревоПереставленныхИсходныхОбъектов != nil)
    }
    @Test("Даже одинаковые OID/mode листьев требуют body и future-link proof")
    func совпадениеЛистьев() throws {
        let р = try мост(пространство([("Инструменты/A/x.md", "100644"), ("instrumentyi/A/x.md", "100644")]))
        #expect(р.контекст == nil && р.деревоПереставленныхИсходныхОбъектов == nil)
        #expect(р.препятствия.contains { $0.код == "не-проверено-совпадение-листьев" && $0.пути.count == 2 })
        #expect(р.отображения.filter { $0.целевой == "instrumentyi/A/x.md" }.count == 2)
    }
    @Test("Тип, префикс и возникший case/NFC alias закрывают весь контекст")
    func конфликты() throws {
        for записи in [
            [("Инструменты/a", "100644"), ("instrumentyi/a/f", "100644")],
            [("Инструменты/A/f", "100644"), ("instrumentyi/a/g", "100644")],
            [("Инструменты/e\u{301}/f", "100644"), ("instrumentyi/é/g", "100644")],
            [("Инструменты/f", "100644"), ("Instrumentyi/g", "100644")],
            [("Инструменты/f", "100644"), ("other/A/f", "100644"), ("other/a/g", "100644")]
        ] {
            let р = try мост(пространство(записи))
            #expect(р.контекст == nil && !р.препятствия.isEmpty && р.деревоПереставленныхИсходныхОбъектов == nil)
        }
    }
    @Test("Канонически равные строки не схлопывают две разные raw collision groups")
    func отдельныеКоллизииUnicode() throws {
        let р = try мост(пространство([
            ("Инструменты/e\u{301}/x", "100644"), ("instrumentyi/e\u{301}/x", "100644"),
            ("Инструменты/é/x", "100644"), ("instrumentyi/é/x", "100644")]))
        let конфликты = р.препятствия.filter { $0.код == "не-проверено-совпадение-листьев" }
        #expect(р.контекст == nil && конфликты.count == 2)
        #expect(Set(конфликты.flatMap(\.пути).map { Data($0.utf8) }).count == 4)
    }
    @Test("Порядок ошибок не зависит от порядка Git-строк и словарей")
    func воспроизводимыеПрепятствия() throws {
        let строки = [("Инструменты/A/f", "100644"), ("instrumentyi/a/g", "100644"),
            ("Инструменты/e\u{301}/x", "100644"), ("instrumentyi/é/y", "100644"), ("Instrumentyi/z", "100644")]
        let исходные = try мост(пространство(строки)).препятствия
        for сдвиг in строки.indices {
            let вход = Array(строки[сдвиг...]) + строки[..<сдвиг]
            let ошибки = try мост(пространство(вход)).препятствия
            #expect(ошибки.map { Data(($0.код + "\0" + $0.пути.joined(separator: "\0")).utf8) }
                == исходные.map { Data(($0.код + "\0" + $0.пути.joined(separator: "\0")).utf8) })
        }
    }
    @Test("Opaque листья остаются непрозрачными, root обязан быть каталогом")
    func непрозрачныеГраницы() throws {
        let р = try мост(пространство([("Инструменты/link", "120000"), ("Инструменты/external", "160000")]))
        let к = try #require(р.контекст)
        #expect(к.будущие[Data("instrumentyi/link".utf8)] == .ссылка && к.будущие[Data("instrumentyi/external".utf8)] == .внешняяГраница)
        let плохой = try мост(пространство([("Инструменты", "120000")]))
        #expect(плохой.контекст == nil && !плохой.препятствия.isEmpty)
    }
    @Test("Отсутствующий source и существующий target не доказывают исполненный повтор")
    func наблюдениеПовтора() throws {
        let р = try мост(пространство([("instrumentyi/f", "100644")]))
        #expect(р.контекст != nil && р.похожеНаПовтор && !р.повторДоказан && !р.применениеРазрешено)
        #expect(р.отображения.allSatisfy { Data($0.исходный.utf8) == Data($0.целевой.utf8) })
        let пустой = try мост(пространство([("other/f", "100644")]))
        #expect(пустой.контекст == nil && !пустой.препятствия.isEmpty && !пустой.похожеНаПовтор)
    }
    @Test("Drift трёх опор и меньшие node/path budgets закрываются до context")
    func опорыИГраницы() throws {
        let вход = try пространство([("Инструменты/f", "100644")])
        for вариант in 0..<3 {
            #expect(throws: (any Error).self) {
                try ПереходПространстваАдресов.построить(вход, ожидаемоеДерево: вариант == 0 ? String(repeating: "2", count: 40) : вход.дерево,
                    ожидаемыйХэшИндекса: вариант == 1 ? String(repeating: "2", count: 64) : вход.хэшИндекса,
                    ожидаемыйХэшПеречня: вариант == 2 ? String(repeating: "2", count: 64) : вход.хэшСырогоПеречня, корень: корень, исключитьПроекцию: true)
            }
        }
        for (узлы, байты) in [(1, 67_108_864), (100_000, 1)] {
            #expect(throws: (any Error).self) {
                try ПереходПространстваАдресов.построить(вход, ожидаемоеДерево: вход.дерево, ожидаемыйХэшИндекса: вход.хэшИндекса,
                    ожидаемыйХэшПеречня: вход.хэшСырогоПеречня, корень: корень, исключитьПроекцию: true, пределУзлов: узлы, пределБайтовПутей: байты)
            }
        }
    }
    @Test("Закреплённые 37662 Git-листа дают только namespace tree прежних объектов",
          .enabled(if: ProcessInfo.processInfo.environment["ФУМ_ПЕРЕЧЕНЬ_ДЕРЕВА_GIT"] != nil))
    func адресныйМост() throws {
        let среда = ProcessInfo.processInfo.environment, читатель = ПроверкиРазмещенияТекста()
        let путьДерева = try #require(среда["ФУМ_ПЕРЕЧЕНЬ_ДЕРЕВА_GIT"]), путьИндекса = try #require(среда["ФУМ_ИНДЕКС_ДЕРЕВА_GIT"])
        let дерево = try читатель.ограниченно(путьДерева, предел: 16_777_216), индекс = try читатель.ограниченно(путьИндекса, предел: 16_777_216)
        try #require(хэшПутей(дерево) == "736e9490e5b6c335895bdbaf57ed5c1d0137fd6cccdcfd49ebffc7a5e1ce8755")
        let вход = try ПространствоИмёнGit.проверить(переченьДерева: дерево, индекс: индекс,
            ожидаемоеДерево: "4fccd93a88d891731314ccf0ed5b69948b94e612", ожидаемыйХэшИндекса: "0cdf082404e0aab0fdbe4dcfe92604b610b87c35c6e356bed88f2d336d1ca86f")
        let р = try мост(вход), к = try #require(р.контекст)
        #expect(р.препятствия.isEmpty && р.удаляемыеЛистья.count == 12_025 && к.исходные.count == 45_812)
        #expect(р.деревоПереставленныхИсходныхОбъектов == "fd5b31eb93f09672e93565b809ba7bdb3f0505fc")
        #expect(р.отображения.filter { $0.исходный.utf8.starts(with: "Инструменты/".utf8) || $0.исходный == "Инструменты" }.count == 1394)
        #expect(к.будущие[Data("instrumentyi".utf8)] == .каталог && к.будущие[Data("Инструменты".utf8)] == nil)
        #expect(!р.применениеРазрешено && !р.повторДоказан && !р.собственныеВходыВключены)
        if let путь = среда["ФУМ_КВИТАНЦИЯ_МОСТА_GIT"] {
            let деревоНазначения = try #require(р.деревоПереставленныхИсходныхОбъектов)
            let квитанция: [String: Any] = ["схема": "fum.адресная-проверка-моста-пространства.1", "деревоИсточника": вход.дерево,
                "хэшИндекса": вход.хэшИндекса, "хэшСырогоПеречня": вход.хэшСырогоПеречня, "хэшОпоры": р.хэшОпоры,
                "хэшКонтекста": к.хэшСостава, "исходныеУзлы": к.исходные.count, "будущиеУзлы": к.будущие.count,
                "отображения": р.отображения.count, "удаляемыеЛистья": р.удаляемыеЛистья.count,
                "деревоПереставленныхИсходныхОбъектов": деревоНазначения,
                "содержимоеОбъектовПроверено": false, "файловаяСистемаПроверена": false, "собственныеВходыВключены": false, "применениеРазрешено": false]
            try (JSONSerialization.data(withJSONObject: квитанция, options: [.prettyPrinted, .sortedKeys]) + Data([10]))
                .write(to: URL(fileURLWithPath: путь), options: .withoutOverwriting)
        }
    }
}

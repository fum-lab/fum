import Foundation
import Testing
#if !ФУМ_ОБЩАЯ_МИГРАЦИЯ_ТЕСТ
@testable import АктуализацияПутей
#endif

@Suite("Выбор областей снимка сохраняет лексическую семантику")
struct ПроверкиВыбораОбластей {
    @Test("Путь внутри области и предок области различаются")
    func предкиИПотомки() {
        let выбор = ВыборОбластейСнимка(области: ["a/b"])
        #expect(выбор.затрагивает("a") && !выбор.содержит("a"))
        #expect(выбор.затрагивает("a/b") && выбор.содержит("a/b"))
        #expect(выбор.затрагивает("a/b/c") && выбор.содержит("a/b/c"))
        #expect(!выбор.затрагивает("a/bb") && !выбор.содержит("a/bb"))
        #expect(!выбор.затрагивает("") && !выбор.содержит(""))
    }

    @Test("NFC используется только для поиска, регистр не складывается")
    func нормализацияИРегистр() {
        let выбор = ВыборОбластейСнимка(области: ["c/é.md", "Инструменты/tool"])
        #expect(выбор.содержит("c/e\u{301}.md"))
        #expect(выбор.затрагивает("c"))
        #expect(!выбор.содержит("C/é.md"))
        #expect(выбор.содержит("Инструменты/tool/x"))
        #expect(!выбор.содержит("Инструменты/toolbox/x"))
    }

    @Test("Индексный выбор эквивалентен прежнему предикату на конечной матрице")
    func прежнийПредикат() {
        let области = ["a/b", "Инструменты/tool", "c/é.md"], выбор = ВыборОбластейСнимка(области: области)
        let пути = ["", "a", "a/b", "a/b/c", "a/bb", "a2/b", "Инструменты", "Инструменты/tool", "Инструменты/tool/x", "Инструменты2", "c", "c/é.md", "c/e\u{301}.md", "C/é.md", "/a", "other"]
        for путь in пути {
            let нормальный = путь.precomposedStringWithCanonicalMapping
            let старыйВнутри = области.contains { ИменаПутей.вложен(нормальный, в: $0.precomposedStringWithCanonicalMapping) }
            let старыйВыбран = старыйВнутри || области.contains { ИменаПутей.вложен($0.precomposedStringWithCanonicalMapping, в: нормальный) }
            #expect(выбор.содержит(путь) == старыйВнутри)
            #expect(выбор.затрагивает(путь) == старыйВыбран)
        }
    }
}

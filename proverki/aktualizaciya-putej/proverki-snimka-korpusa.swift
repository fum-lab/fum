@Suite("Физический снимок корпуса по независимым ожидаемым байтам")
struct ПроверкиСнимкаКорпуса {
    let фикстуры = ПроверкиИнвентаряОбщейМиграции()
    func источник(_ корень: URL, _ основа: ОсноваОбщейМиграции, файлы: [[String: Any]] = []) throws -> Data {
        try JSONSerialization.data(withJSONObject: ["schema": "fum.private-source-checkpoint.1", "root": корень.path, "HEAD": основа.коммит, "ref": основа.ветка, "files": файлы, "openJournal": []], options: [.sortedKeys, .prettyPrinted])
    }
    func вход(_ корень: URL, _ основа: ОсноваОбщейМиграции, источник: Data, пути: [String] = ["Инструменты/X/SKILL.md"], дополнительные: [ФайлОжиданияКорпуса] = []) throws -> Data {
        var документы: [ФайлОжиданияКорпуса] = []
        let индекс = try фикстуры.гит(корень, ["ls-files", "--stage", "-z"])
        for путь in пути {
            let строка = try #require(индекс.split(separator: 0).map { String(decoding: $0, as: UTF8.self) }.first { запись in
                guard let табуляция = запись.firstIndex(of: "\t") else { return false }
                return Data(запись[запись.index(after: табуляция)...].utf8) == Data(путь.utf8)
            })
            let поля = строка.prefix(while: { $0 != "\t" }).split(separator: " ")
            try #require(поля.count == 3)
            let объект = String(поля[1]), данные = try фикстуры.гит(корень, ["cat-file", "blob", объект])
            документы.append(.init(путь: путь, хэш: хэшПутей(данные), режим: String(поля[0]), размер: данные.count, объект: объект, происхождение: "Git-фикстура", класс: "отслеживаемый"))
        }
        документы += дополнительные
        let модель = ОжиданиеСнимкаКорпуса(основа: основа, политикаГраницХэш: "5a52f1134876854e29db243cbfc6eebc86cc916a4d354ba73a0fc7516109bcd4", источникСобственныхХэш: хэшПутей(источник),
            всеМетаданныеХэш: хэшПутей(try фикстуры.гит(корень, ["ls-files", "--cached", "--others", "-z"])), документы: документы)
        return try байтыПлана(модель)
    }

    @Test("Git-ожидание сверяется с ФС, роли не угадываются")
    func независимоеЧтение() async throws {
        try await фикстуры.фикстура { корень, основа in
            let собственный = try источник(корень, основа), ожидание = try вход(корень, основа, источник: собственный)
            let результат = try ЧитательДокументовКорпуса.снять(корень: корень, ожидание: ожидание, собственныйИсточник: собственный)
            try #require(результат.документы.count == 1)
            #expect(результат.документы.first?.байты == Data("x".utf8))
            #expect(результат.документы.first?.роль == .неизвестный)
            #expect(результат.квитанция.учётБайтовПроверен)
            #expect(!результат.квитанция.ролиПроверены && !результат.квитанция.ссылкиПроверены && !результат.квитанция.применениеРазрешено)
        }
    }

    @Test("Изменённые байты и новый MD после исходной инвентаризации закрывают снимок")
    func дрейфИПозднийДокумент() async throws {
        for вариант in 0..<2 {
            try await фикстуры.фикстура { корень, основа in
                let собственный = try источник(корень, основа), ожидание = try вход(корень, основа, источник: собственный)
                if вариант == 0 { try фикстуры.файл(корень, "Инструменты/X/SKILL.md", "изменено") }
                #expect(throws: (any Error).self) {
                    try ЧитательДокументовКорпуса.снять(корень: корень, ожидание: ожидание, собственныйИсточник: собственный,
                        передСнимкомДляПроверки: вариант == 1 ? { try фикстуры.файл(корень, "new/not-selected.md", "новый") } : nil)
                }
            }
        }
    }

    @Test("Собственный untracked принимается только из отдельного закреплённого списка")
    func собственныйДокумент() async throws {
        try await фикстуры.фикстура { корень, основа in
            try фикстуры.файл(корень, "own.md", "own")
            let запись = ФайлОжиданияКорпуса(путь: "own.md", хэш: хэшПутей(Data("own".utf8)), режим: "100644", размер: 3, объект: nil, происхождение: "собственная-фикстура", класс: "собственный-неотслеживаемый")
            let пустойИсточник = try источник(корень, основа), неверныйВход = try вход(корень, основа, источник: пустойИсточник, дополнительные: [запись])
            #expect(throws: (any Error).self) { try ЧитательДокументовКорпуса.снять(корень: корень, ожидание: неверныйВход, собственныйИсточник: пустойИсточник) }
            let собственный = try источник(корень, основа, файлы: [["path": "own.md", "sha256": запись.хэш, "bytes": 3, "mode": "100644"]])
            let верныйВход = try вход(корень, основа, источник: собственный, дополнительные: [запись])
            let результат = try ЧитательДокументовКорпуса.снять(корень: корень, ожидание: верныйВход, собственныйИсточник: собственный)
            #expect(результат.документы.count == 2)
            #expect(результат.квитанция.документы.contains { $0.путь == "own.md" && $0.класс == "собственный-неотслеживаемый" })
        }
    }

    @Test("Git-NFD и физический путь остаются раздельными")
    func одиночныйNFD() async throws {
        try await фикстуры.фикстура { корень, основа in
            let путь = "Инструменты/e\u{301}/doc.md"
            try фикстуры.файл(корень, путь)
            _ = try фикстуры.гит(корень, ["-c", "core.precomposeunicode=false", "add", "--all"])
            _ = try фикстуры.гит(корень, ["commit", "--quiet", "-m", "fixture NFD corpus"])
            let новая = try фикстуры.новаяОснова(корень, основа), собственный = try источник(корень, новая)
            let ожидание = try вход(корень, новая, источник: собственный, пути: ["Инструменты/X/SKILL.md", путь])
            let результат = try ЧитательДокументовКорпуса.снять(корень: корень, ожидание: ожидание, собственныйИсточник: собственный)
            #expect(результат.квитанция.документы.contains { Data($0.путь.utf8) == Data(путь.utf8) })
            try #require(!результат.квитанция.алиасыИнвентаризации.isEmpty)
            let ожидаемые = Set(["Инструменты/X/SKILL.md", путь].map { Data($0.utf8) } + результат.квитанция.алиасыИнвентаризации.map { Data($0.путьМетаданных.utf8) })
            #expect(Set(результат.квитанция.точноОткрытыеОбласти.map { Data($0.utf8) }) == ожидаемые)
            #expect(результат.квитанция.точноОткрытыеОбласти.count == ожидаемые.count)
        }
    }

    @Test("Предел чтения отдельного файла отличается от предела сохранения")
    func пределЧитаемогоФайла() async throws {
        try await фикстуры.фикстура { корень, _ in
            #expect(throws: (any Error).self) {
                try ЧитательПутей.снять(корень: корень, области: ["Инструменты/X/SKILL.md"], пределСохраняемогоФайла: 0, пределЧитаемогоФайла: 0)
            }
            let результат = try ЧитательПутей.снять(корень: корень, области: ["Инструменты/X/SKILL.md"], пределСохраняемогоФайла: 0, пределЧитаемогоФайла: 1)
            #expect(результат.тексты.isEmpty)
            #expect(результат.снимок.записи.contains { $0.путь == "Инструменты/X/SKILL.md" && $0.sha256 == хэшПутей(Data("x".utf8)) })
        }
    }

    @Test("Поздняя смена ref после глобальной инвентаризации закрывает снимок")
    func поздняяСменаВетки() async throws {
        try await фикстуры.фикстура { корень, основа in
            _ = try фикстуры.гит(корень, ["update-ref", "refs/heads/fixture-late", основа.коммит])
            let собственный = try источник(корень, основа), ожидание = try вход(корень, основа, источник: собственный)
            #expect(throws: (any Error).self) {
                try ЧитательДокументовКорпуса.снять(корень: корень, ожидание: ожидание, собственныйИсточник: собственный,
                    послеИнвентаризацииДляПроверки: { _ = try фикстуры.гит(корень, ["symbolic-ref", "HEAD", "refs/heads/fixture-late"]) })
            }
        }
    }
}

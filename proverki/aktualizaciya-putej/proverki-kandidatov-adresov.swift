                синтаксисПолностьюРаспознан: true, узлы: [], ошибки: [], неизвестныеДиапазоны: [], скрытыеДиапазоны: [], эвристическиЗащищённыеДиапазоны: [], неподдержанныеКонтейнеры: [])

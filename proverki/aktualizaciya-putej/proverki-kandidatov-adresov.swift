    @Test("Начальный combining mark не склеивает slash с именем и не меняет базу")
    func побайтовыеРазделители() throws {
        let имя = "\u{301}x.md", старыйПуть = "dir/" + имя, новыйПуть = "new/" + имя
        let старые = [цель("dir", .каталог), цель(старыйПуть), цель("dir/f"), цель("f")]
        let новые = [цель("dir", .каталог), цель("dir/f"), цель("f"), цель("new", .каталог), цель(новыйПуть)]
        let к = try контекст(старые, новые, [(старыйПуть, новыйПуть)])
        let р = разобрать("[x](f)", путь: старыйПуть, контекст: к)
        #expect(р.вхождения.first?.прежняяЦель == "dir/f")
        #expect(р.вхождения.first?.новыйПутьАдреса == "../dir/f")
        let общий = try ПроверкиСсылокОбщейМиграции().разрешить([(старыйПуть, "[x](f)")], [(старыйПуть, новыйПуть)], [старыйПуть, "dir/f", "f"])
        #expect(общий[старыйПуть]?.байтыПосле == Data("[x](../dir/f)".utf8))
        let узлы = [цель("dir", .каталог), цель("dir/x.md"), цель("\u{301}f")], обычный = try контекст(узлы, узлы)
        let закодированный = разобрать("[x](../%CC%81f)", путь: "dir/x.md", контекст: обычный)
        #expect(закодированный.вхождения.first?.вид == .локальный && закодированный.вхождения.first?.прежняяЦель == "\u{301}f")
    }

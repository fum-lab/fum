@Suite("Условные кандидаты адресов без переписывания документа")
struct ПроверкиКандидатовАдресов {
    func цель(_ путь: String, _ вид: ВидУзлаМиграции = .файл) -> ЦельПространстваАдресов { .init(путь: путь, вид: вид) }
    func контекст(_ старые: [ЦельПространстваАдресов], _ новые: [ЦельПространстваАдресов], _ пары: [(String, String)] = [], удаляемые: [String] = [], опора: String = String(repeating: "1", count: 64)) throws -> КонтекстКандидатовАдресов {
        try .подготовить(исходные: старые, будущие: новые, соответствия: пары.map { .init(исходный: $0.0, целевой: $0.1) }, удаляемые: удаляемые, хэшОпоры: опора)
    }
    func разобрать(_ текст: String, путь: String, контекст: КонтекстКандидатовАдресов) -> КандидатыРазрешенияДокумента {
        let документ = ПроверкиПеречняАдресов().документ(текст, путь: путь)
        return РешательСсылокПакета.диагностироватьРазрешение(документ, перечень: РешательСсылокПакета.перечислитьАдреса(документ),
            контекст: контекст, ожидаемыйХэшКонтекста: контекст.хэшСостава)
    }
    @Test("Definition URI хранится один раз, каждое повторное упоминание отдельно")
    func повторныеСсылки() throws {
        let к = try контекст([цель("docs", .каталог), цель("docs/x.md"), цель("a", .каталог), цель("a/f")],
            [цель("docs", .каталог), цель("docs/x.md"), цель("b", .каталог), цель("b/f")], [("a", "b"), ("a/f", "b/f")])
        let р = разобрать("[x][r] [r][] [r]\n[r]: ../a/f?q=%GG#я\n[direct](../a/f)\n", путь: "docs/x.md", контекст: к)
        #expect(р.всеЗаявленныеУзлыУчтены && р.вхождения.count == 2 && р.упоминания.count == 3)
        #expect(р.вхождения.allSatisfy { $0.будущаяЦель == "b/f" && $0.новыйПутьАдреса == "../b/f" })
        #expect(Set(р.упоминания.compactMap(\.вхождение)).count == 1)
        #expect(!р.происхождениеПеречняПроверено && !р.ролиПроверены && !р.целиПроверены && !р.якоряИЗапросыПроверены && !р.применениеРазрешено)
    }
    @Test("Разные исходные базы при одном будущем документе дают разные адреса")
    func разныеБазы() throws {
        let старые = [цель("a", .каталог), цель("a/x.md"), цель("a/f"), цель("b", .каталог), цель("b/x.md"), цель("b/f")]
        let новые = [цель("common", .каталог), цель("common/x.md"), цель("a", .каталог), цель("a/f"), цель("b", .каталог), цель("b/f")]
        let к = try контекст(старые, новые, [("a/x.md", "common/x.md"), ("b/x.md", "common/x.md")])
        let а = разобрать("[x](f)", путь: "a/x.md", контекст: к), б = разобрать("[x](f)", путь: "b/x.md", контекст: к)
        #expect(а.вхождения.first?.новыйПутьАдреса == "../a/f")
        #expect(б.вхождения.first?.новыйПутьАдреса == "../b/f")
    }
    @Test("Ошибки URI и неоднозначные метки сохраняют последующего успешного соседа")
    func независимыеОшибки() throws {
        let узлы = [цель("docs", .каталог), цель("docs/x.md"), цель("docs/good")]
        let к = try контекст(узлы, узлы)
        let р = разобрать("[bad](bad%GG) [ok](good) [u][missing]\n[r]: good\n[r]: good\n[x][r]\n", путь: "docs/x.md", контекст: к)
        #expect(р.всеЗаявленныеУзлыУчтены && р.вхождения.contains { $0.вид == .отказ } && р.вхождения.contains { $0.вид == .локальный && $0.прежняяЦель == "docs/good" })
        #expect(р.упоминания.count == 2 && р.упоминания.allSatisfy { $0.ошибка != nil })
        #expect(р.упоминания.contains { $0.определения.count == 2 && $0.вхождение == nil })
    }
    @Test("Каталог и синтетический корень различаются с непрозрачной границей и удаляемой проекцией")
    func видыИГраницы() throws {
        let старые = [цель("docs", .каталог), цель("docs/x.md"), цель("dir", .каталог), цель("link", .ссылка), цель("external", .внешняяГраница), цель("Proyekcii", .каталог), цель("Proyekcii/f")]
        let новые = старые.filter { !$0.путь.hasPrefix("Proyekcii") }
        let к = try контекст(старые, новые, удаляемые: ["Proyekcii"])
        let р = разобрать("[d](../dir/) [root](../) [s](../link) [e](../external/f) [p](../Proyekcii/f)", путь: "docs/x.md", контекст: к)
        #expect(р.вхождения.filter { $0.вид == .локальный }.count == 2)
        #expect(р.вхождения.filter { $0.вид == .непрозрачнаяГраница }.count == 2)
        #expect(р.вхождения.filter { $0.вид == .удаляемый }.count == 1)
    }
    @Test("Угловые пробелы и непрозрачный suffix сохраняют исходные байты")
    func угловаяФормаИСуффикс() throws {
        let к = try контекст([цель("old", .каталог), цель("old/x.md"), цель("old/a b")],
            [цель("new", .каталог), цель("new/x.md"), цель("old", .каталог), цель("old/a b")], [("old/x.md", "new/x.md")])
        let текст = "[x](<a b?q=%GG#я>)", документ = ПроверкиПеречняАдресов().документ(текст, путь: "old/x.md")
        let р = РешательСсылокПакета.диагностироватьРазрешение(документ, перечень: РешательСсылокПакета.перечислитьАдреса(документ), контекст: к, ожидаемыйХэшКонтекста: к.хэшСостава)
        let адрес = try #require(р.вхождения.first)
        #expect(адрес.новыйПутьАдреса == "../old/a b")
        #expect(документ.байты.subdata(in: адрес.суффикс) == Data("?q=%GG#я".utf8))
        #expect(!р.применениеРазрешено)
    }
    @Test("Контекст отвергает дубли, недиректориальных предков и несовпадение видов")
    func плохойКонтекст() {
        #expect(throws: (any Error).self) { try контекст([цель("a"), цель("a")], [цель("a")]) }
        #expect(throws: (any Error).self) { try контекст([цель("a"), цель("a/b")], [цель("a")]) }
        #expect(throws: (any Error).self) { try контекст([цель("a")], [цель("b", .каталог)], [("a", "b")]) }
        #expect(throws: (any Error).self) { try контекст([цель("a")], [цель("a")], опора: "bad") }
    }
    @Test("Хэш связывает исходные/будущие имена, отображение, удаление и опору")
    func отпечатокКонтекста() throws {
        let узлы = [цель("a"), цель("b")], а = try контекст(узлы, узлы), б = try контекст(Array(узлы.reversed()), Array(узлы.reversed()))
        let в = try контекст(узлы, узлы, [("a", "b")])
        #expect(а.хэшСостава == б.хэшСостава && а.хэшСостава != в.хэшСостава)
        // Независимый Node SHA-256: длины UInt64 BE и точные UTF-8 поля.
        #expect(а.хэшСостава == "ae8ef5c32b09cedf18cc610719a79518b204c6d4654a8fac9185597db926b8b3")
        let другаяОпора = try контекст(узлы, узлы, опора: String(repeating: "2", count: 64))
        #expect(а.хэшСостава != другаяОпора.хэшСостава)
    }
    @Test("Алиасы предков и NFC-вместо-NFD не становятся точным попаданием")
    func точностьИмён() throws {
        let узлы = [цель("docs", .каталог), цель("docs/x.md"), цель("A", .каталог), цель("A/f"), цель("a", .каталог), цель("a/g"), цель("e\u{301}")]
        let к = try контекст(узлы, узлы)
        let р = разобрать("[x](../A/f) [n](../é)", путь: "docs/x.md", контекст: к)
        #expect(р.вхождения.count == 2 && р.вхождения.allSatisfy { $0.вид == .отказ })
        #expect(р.вхождения.first?.ошибка == "алиас-исходной-цели-кандидата")
        #expect(р.вхождения.last?.ошибка == "нет-точной-старой-цели")
    }
    @Test("Локальный лимит адреса сохраняет соседа, общий бюджет не выдаёт частичный успех")
    func пределыКандидатов() throws {
        let узлы = [цель("docs", .каталог), цель("docs/x.md"), цель("docs/bad"), цель("docs/f")], к = try контекст(узлы, узлы)
        let вход = ПроверкиПеречняАдресов().документ("[long](bad) [short](f)", путь: "docs/x.md"), перечень = РешательСсылокПакета.перечислитьАдреса(вход)
        var предел = ПределыКандидатовАдресов(); предел.байтыАдреса = 1
        let р = РешательСсылокПакета.диагностироватьРазрешение(вход, перечень: перечень, контекст: к, ожидаемыйХэшКонтекста: к.хэшСостава, пределы: предел)
        #expect(р.вхождения.count == 2 && р.вхождения.first?.хэшАдреса == nil && р.вхождения.last?.вид == .локальный)
        предел = .init(); предел.шаги = вход.байты.count - 1
        let закрытый = РешательСсылокПакета.диагностироватьРазрешение(вход, перечень: перечень, контекст: к, ожидаемыйХэшКонтекста: к.хэшСостава, пределы: предел)
        #expect(!закрытый.всеЗаявленныеУзлыУчтены && закрытый.вхождения.isEmpty && !закрытый.применениеРазрешено)
    }
    @Test("Неверный pin и поддельный диапазон внутри UTF-8 закрываются до URI")

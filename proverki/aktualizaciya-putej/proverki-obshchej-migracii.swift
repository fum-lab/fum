@Suite("Читающий инвентарь общей миграции")
struct ПроверкиИнвентаряОбщейМиграции {
    func гит(_ корень: URL, _ аргументы: [String]) throws -> Data {
        let процесс = Process(); процесс.executableURL = URL(fileURLWithPath: "/usr/bin/git")
        процесс.arguments = ["-C", корень.path, "-c", "user.name=fixture", "-c", "user.email=fixture@example.invalid", "-c", "core.hooksPath=/dev/null", "-c", "commit.gpgSign=false"] + аргументы
        var среда = ProcessInfo.processInfo.environment.filter { !$0.key.hasPrefix("GIT_") }
        среда["GIT_CONFIG_NOSYSTEM"] = "1"; среда["GIT_CONFIG_GLOBAL"] = "/dev/null"; процесс.environment = среда
        let канал = Pipe(); процесс.standardOutput = канал; процесс.standardError = FileHandle.nullDevice
        try процесс.run(); let данные = канал.fileHandleForReading.readDataToEndOfFile(); процесс.waitUntilExit()
        guard процесс.terminationStatus == 0 else { throw ОтказОбщейМиграции.условие("fixture-git") }; return данные
    }
    func файл(_ корень: URL, _ путь: String, _ текст: String = "x") throws {
        let адрес = корень.appendingPathComponent(путь)
        try FileManager.default.createDirectory(at: адрес.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(текст.utf8).write(to: адрес)
    }
    func фикстура(_ действие: (URL, ОсноваОбщейМиграции) async throws -> Void) async throws {
        let временный = FileManager.default.temporaryDirectory.appendingPathComponent("fum-obshchaya-migraciya-" + UUID().uuidString)
        try FileManager.default.createDirectory(at: временный, withIntermediateDirectories: false)
        let корень = временный.resolvingSymlinksInPath(); defer { try? FileManager.default.removeItem(at: корень) }
        _ = try гит(корень, ["init", "--quiet", "--initial-branch=fixture"])
        try файл(корень, "Инструменты/X/SKILL.md"); try файл(корень, "Proyekcii/copy.txt", "копия")
        _ = try гит(корень, ["add", "--all"]); _ = try гит(корень, ["commit", "--quiet", "-m", "fixture"])
        func строка(_ аргументы: [String]) throws -> String { String(decoding: try гит(корень, аргументы), as: UTF8.self).trimmingCharacters(in: .newlines) }
        let основа = ОсноваОбщейМиграции(корневаяЗадача: "01a07d3d-d376-7ad2-aafc-67e4c25a67eb", владелец: "fixture",
            ветка: try строка(["symbolic-ref", "HEAD"]), коммит: try строка(["rev-parse", "HEAD"]), дерево: try строка(["rev-parse", "HEAD^{tree}"]), индексSHA256: хэшПутей(try гит(корень, ["ls-files", "--stage", "-z"])))
        try await действие(корень, основа)
    }
    func новаяОснова(_ корень: URL, _ прежняя: ОсноваОбщейМиграции) throws -> ОсноваОбщейМиграции {
        var новая = прежняя
        новая.коммит = String(decoding: try гит(корень, ["rev-parse", "HEAD"]), as: UTF8.self).trimmingCharacters(in: .newlines)
        новая.дерево = String(decoding: try гит(корень, ["rev-parse", "HEAD^{tree}"]), as: UTF8.self).trimmingCharacters(in: .newlines)
        новая.индексSHA256 = хэшПутей(try гит(корень, ["ls-files", "--stage", "-z"]))
        return новая
    }


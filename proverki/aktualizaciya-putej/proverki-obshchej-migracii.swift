        for (узлы, корни) in случаи { #expect(!(try план(узлы, корни)).препятствия.isEmpty) }
    }

    @Test("Неверное происхождение отвергается, replay связан с точными байтами")
    func происхождениеИПовтор() throws {
        var иная = основа; иная.дерево = String(repeating: "e", count: 40)
        #expect(throws: (any Error).self) { try ОбщийПланировщикПутей.построить(основа: основа, ожидаемаяОснова: иная, узлы: [], корни: []) }
        let узлы = [каталог("a"), файл("a/f")]
        let один = try план(узлы, [корень("a", "b")]), два = try план(узлы.reversed(), [корень("a", "b")])
        let байты = try ОбщийПланировщикПутей.байты(один)
        #expect(try ОбщийПланировщикПутей.байты(два) == байты)
        try ОбщийПланировщикПутей.сверить(байты, sha256: ОбщийПланировщикПутей.хэш(байты), текущий: два)
        let завершённый = try план([каталог("b"), файл("b/f")], [корень("a", "b")])
        #expect(завершённый.группы.allSatisfy { $0.вид == .неподвижная })
    }

    @Test("План связывает будущие байты, цели и происхождение имени")
    func полнотаОтпечатка() throws {

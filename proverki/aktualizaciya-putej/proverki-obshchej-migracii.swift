        let первый = try план(узлы, [корень("a", "b")], документы: документ("один"))
        let второй = try план(узлы, [корень("a", "b")], документы: документ("два"))
        #expect(try ОбщийПланировщикПутей.байты(первый) != ОбщийПланировщикПутей.байты(второй))
        var другоеИмя = корень("a", "b"); другоеИмя.источникИмени = "другое-происхождение"

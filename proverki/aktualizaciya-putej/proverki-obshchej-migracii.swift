@Suite("Ссылки общей миграции от старого и будущего документа")
struct ПроверкиСсылокОбщейМиграции {
    func разрешить(_ тексты: [(String, String)], _ пары: [(String, String)], _ пути: [String], удалённые: [String] = [], дословные: [String] = []) throws -> [String: РазрешённыйДокументМиграции] {
        let документы = тексты.map { ДокументСсылокПакета(путь: $0.0, байты: Data($0.1.utf8), sha256: хэшПутей(Data($0.1.utf8))) }
        let отображения = пары.map { СтрокаОбщегоОтображения(исходный: $0.0, целевой: $0.1) }
        let удалено = Set(удалённые.map { Data($0.utf8) })
        let словарь = Dictionary(uniqueKeysWithValues: пары.map { (Data($0.0.utf8), $0.1) })
        let будущие = Set(пути.filter { !удалено.contains(Data($0.utf8)) }.map { Data((словарь[Data($0.utf8)] ?? $0).utf8) })
        return try РешательСсылокПакета.разрешитьМиграцию(документы: документы, ожидаемыеПути: тексты.map(\.0), отображения: отображения,
            исходныеПути: Set(пути.map { Data($0.utf8) }), конечныеПути: будущие, удалённыеПути: удалено, дословныеДокументы: Set(дословные.map { Data($0.utf8) }))
    }

    @Test("Входящая ссылка третьей папки получает будущее имя цели")
    func входящая() throws {
        let результат = try разрешить([("docs/x.md", "[x](../Инструменты/X/README.md#p)")], [("Инструменты/X/README.md", "instrumentyi/X/README.md")], ["docs/x.md", "Инструменты/X/README.md"])
        #expect(результат["docs/x.md"]?.байтыПосле == Data("[x](../instrumentyi/X/README.md#p)".utf8))
        #expect(результат["docs/x.md"]?.полнотаПроверена == true)
    }

    @Test("Исходящая ссылка перемещённого документа сохраняет неподвижную цель")
    func исходящая() throws {
        let результат = try разрешить([("old/docs/x.md", "[x](../shared.md?q#p) [self](#here)")], [("old/docs/x.md", "new/docs/x.md")], ["old/docs/x.md", "old/shared.md"])
        #expect(результат["old/docs/x.md"]?.байтыПосле == Data("[x](../../old/shared.md?q#p) [self](#here)".utf8))
        #expect(результат["old/docs/x.md"]?.целиПосле == ["old/shared.md", "new/docs/x.md"])
    }

    @Test("Равные исходные байты с разными базами получают разные будущие адреса")
    func разныеБазы() throws {
        let результат = try разрешить([("a/docs/x.md", "[r](../shared.md)"), ("b/docs/x.md", "[r](../shared.md)")],
            [("a/docs/x.md", "common/x.md"), ("b/docs/x.md", "common/x.md")], ["a/docs/x.md", "b/docs/x.md", "a/shared.md", "b/shared.md"])
        #expect(результат["a/docs/x.md"]?.байтыПосле == Data("[r](../a/shared.md)".utf8))
        #expect(результат["b/docs/x.md"]?.байтыПосле == Data("[r](../b/shared.md)".utf8))
    }

    @Test("Удалённая проекция и неподдержанные адреса закрываются явно")
    func неподдержанные() throws {
        for текст in ["[x](../Proyekcii/x.md)", "[[../x.md]]", "<a href=\"../x.md\">x</a>", "```\n[x](../x.md)", "<!-- open", "[x](../a%2fb.md)"] {
            #expect(throws: (any Error).self) { try разрешить([("old/x.md", текст)], [("old/x.md", "new/x.md")], ["old/x.md", "Proyekcii/x.md", "x.md"], удалённые: ["Proyekcii/x.md"]) }
        }
    }

    @Test("Дословный источник сохраняется, общий definition не правится за ним")
    func дословное() throws {
        let исходный = "[x](../a/f)\n"
        let результат = try разрешить([("Источники/x.md", исходный)], [("a/f", "b/f")], ["Источники/x.md", "a/f"], дословные: ["Источники/x.md"])
        #expect(результат["Источники/x.md"]?.байтыПосле == Data(исходный.utf8))
        let запрос = "## Текст запроса\n[x][r]\n## Решение\n[y][r]\n[r]: ../../a/f\n"
        #expect(throws: (any Error).self) { try разрешить([("Журнал/fixture/запрос.md", запрос)], [("a/f", "b/f")], ["Журнал/fixture/запрос.md", "a/f"]) }
    }

    @Test("Активная reference-ссылка не скрывается за дословным definition")
    func дословноеОпределение() throws {
        let текст = "## Текст запроса\n[r]: ../../a/f\n## Решение\n[x][r]\n"
        #expect(throws: (any Error).self) { try разрешить([("Журнал/fixture/запрос.md", текст)], [("a/f", "b/f")], ["Журнал/fixture/запрос.md", "a/f"]) }
    }

    @Test("Смена глубины документа допускает перестроение старого адреса")
    func глубинаДокумента() throws {
        let результат = try разрешить([("a/b/x.md", "[x](../../t.md)")], [("a/b/x.md", "new/x.md")], ["a/b/x.md", "t.md"])
        #expect(результат["a/b/x.md"]?.байтыПосле == Data("[x](../t.md)".utf8))
    }

    @Test("Исторический batch9 сохраняет прежний вход и результат")
    func прежнийКонтракт() throws {
        let текст = Data("[x](../old0.md)".utf8)
        let документ = ДокументСсылокПакета(путь: "docs/x.md", байты: текст, sha256: хэшПутей(текст))
        let пары = (0..<9).map { ОтображениеПути(исходный: "old\($0).md", целевой: "new\($0).md") }
        let результат = try РешательСсылокПакета.разрешить(документы: [документ], ожидаемыеПути: [документ.путь], пары: пары, разрешённыеДокументы: [документ.путь], проверитьАдрес: { _ in })
        #expect(результат.first?.будущиеБайты == Data("[x](../new0.md)".utf8))
        #expect(throws: (any Error).self) { try РешательСсылокПакета.разрешить(документы: [], ожидаемыеПути: [], пары: [], разрешённыеДокументы: [], проверитьАдрес: { _ in }) }
    }

    @Test("RAW prefix и явная роль действуют независимо")
    func независимыеДословныеРоли() throws {
        let исходный = "[x](../a/f)"
        for (путь, дословные) in [("Источники/x.md", [String]()), ("other/x.md", ["other/x.md"])] {
            let результат = try разрешить([(путь, исходный)], [("a/f", "b/f")], [путь, "a/f"], дословные: дословные)
            #expect(результат[путь]?.байтыПосле == Data(исходный.utf8))
        }
    }

    @Test("Независимый expected-корпус отвергает missing, extra и duplicate")
    func независимыйКорпус() throws {
        let документ = ДокументСсылокПакета(путь: "x.md", байты: Data(), sha256: хэшПутей(Data()))
        for (документы, ожидаемые) in [([документ], [String]()), ([ДокументСсылокПакета](), ["x.md"]), ([документ, документ], ["x.md", "x.md"])] {
            #expect(throws: ОтказСсылокПакета.условие("неполный-или-повторный-Markdown-инвентарь")) {
                try РешательСсылокПакета.разрешитьМиграцию(документы: документы, ожидаемыеПути: ожидаемые, отображения: [], исходныеПути: [Data("x.md".utf8)], конечныеПути: [Data("x.md".utf8)])
            }
        }
    }

    @Test("Ссылочные byte ranges относятся к логическому Data slice")
    func срезMarkdown() throws {
        let текст = Data("[x](../a/f)".utf8), сПолем = Data([32]) + текст, срез = сПолем.dropFirst()
        #expect(срез.startIndex != 0)
        let документ = ДокументСсылокПакета(путь: "docs/x.md", байты: срез, sha256: хэшПутей(срез))
        let результат = try РешательСсылокПакета.разрешитьМиграцию(документы: [документ], ожидаемыеПути: [документ.путь], отображения: [.init(исходный: "a/f", целевой: "b/f")],
            исходныеПути: [Data("docs/x.md".utf8), Data("a/f".utf8)], конечныеПути: [Data("docs/x.md".utf8), Data("b/f".utf8)])
        #expect(результат[документ.путь]?.байтыПосле == Data("[x](../b/f)".utf8))
    }

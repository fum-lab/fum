    @Test("File-directory, prefix, case и symlink закрывают преобразование")
    func опасныеСлучаи() throws {
        let случаи: [([УзелОбщейМиграции], [КорневоеОтображениеМиграции])] = [
            ([каталог("a"), файл("a/f"), каталог("b"), каталог("b/f")], [корень("a", "b")]),

@Suite("Общий dryplan перемещения и объединения")
struct ПроверкиОбщейМиграции {
    let основа = ОсноваОбщейМиграции(корневаяЗадача: "01a07d3d-d376-7ad2-aafc-67e4c25a67eb", владелец: "fixture",
        ветка: "refs/heads/fixture", коммит: String(repeating: "a", count: 40), дерево: String(repeating: "b", count: 40), индексSHA256: String(repeating: "c", count: 64))
    func каталог(_ путь: String) -> УзелОбщейМиграции { .init(путь: путь, вид: .каталог, режим: "040000") }
    func файл(_ путь: String, _ текст: String = "x", режим: String = "100644") -> УзелОбщейМиграции {
        .init(путь: путь, вид: .файл, режим: режим, объект: String(repeating: "d", count: 40), байты: Data(текст.utf8))
    }
    func корень(_ из: String, _ в: String) -> КорневоеОтображениеМиграции { .init(исходный: из, целевой: в, источникИмени: "проверочная-фикстура") }
    func план(_ узлы: [УзелОбщейМиграции], _ корни: [КорневоеОтображениеМиграции], документы: [String: РазрешённыйДокументМиграции] = [:]) throws -> ПланОбщейМиграции {
        try ОбщийПланировщикПутей.построить(основа: основа, ожидаемаяОснова: основа, узлы: узлы, корни: корни, документы: документы)
    }

    @Test("Отсутствующее назначение даёт MOVE и сохраняет каждый suffix")
    func переносПриОтсутствии() throws {
        let узлы = [каталог("Инструменты"), каталог("Инструменты/X"), файл("Инструменты/X/SKILL.md")]
        let результат = try план(узлы, [корень("Инструменты", "instrumentyi")], документы: ["Инструменты/X/SKILL.md": .init(байтыПосле: Data("x".utf8), целиПосле: [], полнотаПроверена: true)])
        #expect(результат.отображения.count == 3)
        #expect(результат.отображения.last?.целевой == "instrumentyi/X/SKILL.md")
        #expect(результат.группы.contains { $0.вид == .перенос })
        #expect(результат.препятствия.isEmpty)
        #expect(!результат.применениеРазрешено)
    }

    @Test("UNION сохраняет обе mapping-строки equal leaves")
    func объединениеКаталогов() throws {
        let результат = try план([каталог("a"), файл("a/f"), каталог("b"), файл("b/f")], [корень("a", "b")])
        #expect(результат.отображения.count == 4)
        #expect(результат.группы.contains { $0.вид == .объединениеКаталогов && $0.исходные.count == 2 })
        #expect(результат.группы.contains { $0.вид == .дубликат && $0.исходные.count == 2 })
        #expect(результат.препятствия.isEmpty)
    }

    @Test("Различные bytes или mode блокируют весь план")
    func разныеЛистья() throws {
        for второй in [файл("b/f", "y"), файл("b/f", "x", режим: "100755")] {

    func равныеБайтыРазныеСсылки() throws {
        let текст = "[x](../target.md)"
        let документы = ["a/x.md": РазрешённыйДокументМиграции(байтыПосле: Data(текст.utf8), целиПосле: ["target.md"], полнотаПроверена: true),
            "b/x.md": РазрешённыйДокументМиграции(байтыПосле: Data(текст.utf8), целиПосле: ["other/target.md"], полнотаПроверена: true)]
        let результат = try план([каталог("a"), файл("a/x.md", текст), каталог("b"), файл("b/x.md", текст)], [корень("a", "b")], документы: документы)

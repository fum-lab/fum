import Foundation
import Testing
#if !ФУМ_ОБЩАЯ_МИГРАЦИЯ_ТЕСТ
@testable import АктуализацияПутей
#endif

@Suite("Замкнутые порции диагностики без приёмки исходников")
struct ПроверкиПорцийКандидатов {
    func документ(_ путь: String, _ размер: Int = 1, режим: String = "100644") -> ДокументПланаПорций {
        .init(путь: путь, хэш: String(repeating: "1", count: 64), режим: режим, размер: размер, класс: "отслеживаемый", объект: String(repeating: "1", count: 40))
    }
    func план(_ документы: [ДокументПланаПорций], число: Int = 256, байты: Int = 16_777_216, опора: String = String(repeating: "a", count: 64),
        физическая: String = String(repeating: "b", count: 64), собственная: String = String(repeating: "c", count: 64), контекст: String = String(repeating: "d", count: 64)) throws -> ПланПорцийКандидатов {
        try ПланировщикПорцийКандидатов.построить(документы, хэшОжидания: опора,
            хэшФизическогоСнимка: физическая, хэшСобственногоИсточника: собственная,
            хэшКонтекста: контекст, документовВПорции: число, байтовВПорции: байты)
    }
    @Test("Границы документа и байтов сохраняют каждый исходный ordinal ровно один раз")
    func замкнутоеРазбиение() throws {
        let р = try план([документ("a", 2), документ("b", 3), документ("c", 4), документ("d", 0), документ("e", 2)], число: 2, байты: 5)
        #expect(р.шаги == [.init(начало: 0, конец: 2, байты: 5, допускаетОбход: true), .init(начало: 2, конец: 4, байты: 4, допускаетОбход: true), .init(начало: 4, конец: 5, байты: 2, допускаетОбход: true)])
        #expect(р.документы == 5 && р.байты == 11 && !р.внешниеОпорыПроверены && !р.содержимоеПроверено && !р.ролиПроверены && !р.применениеРазрешено)
    }
    @Test("Singleton сверх бюджета получает отдельный UNKNOWN шаг с продвижением")
    func слишкомБольшойДокумент() throws {
        let р = try план([документ("a", 1), документ("big", 6), документ("c", 1)], байты: 5)
        #expect(р.шаги == [.init(начало: 0, конец: 1, байты: 1, допускаетОбход: true), .init(начало: 1, конец: 2, байты: 6, допускаетОбход: false), .init(начало: 2, конец: 3, байты: 1, допускаетОбход: true)])
    }
    @Test("Хэш связывает порядок, raw имя, SHA, mode, пределы и внешние опоры")
    func точныйОтпечаток() throws {
        let а = документ("e\u{301}"), б = документ("b"), исходный = try план([а, б])
        #expect(исходный.хэшСостава == (try план([а, б])).хэшСостава)
        // Независимый Node SHA-256, 740 байт length-framed входа.
        #expect(исходный.хэшСостава == "08340b7a8c872a897bffb60c2eedeec7b203c7c5f386f1f56626d4d7b82968ad")
        for другой in [try план([б, а]), try план([документ("é"), б]), try план([документ("e\u{301}", режим: "100755"), б]), try план([а, б], число: 1), try план([а, б], опора: String(repeating: "f", count: 64))] {
            #expect(другой.хэшСостава != исходный.хэшСостава)
        }
        let оба = try план([а, документ("é")])
        #expect(оба.документы == 2)
        let собственный = ДокументПланаПорций(путь: а.путь, хэш: а.хэш, режим: а.режим, размер: а.размер, класс: "собственный-неотслеживаемый", объект: nil)
        let инойОбъект = ДокументПланаПорций(путь: а.путь, хэш: а.хэш, режим: а.режим, размер: а.размер, класс: а.класс, объект: String(repeating: "2", count: 40))
        #expect(try план([собственный, б]).хэшСостава != исходный.хэшСостава)
        #expect(try план([инойОбъект, б]).хэшСостава != исходный.хэшСостава)
        let инойХэш = ДокументПланаПорций(путь: а.путь, хэш: String(repeating: "2", count: 64), режим: а.режим, размер: а.размер, класс: а.класс, объект: а.объект)
        for другой in [try план([инойХэш, б]), try план([документ(а.путь, 2), б]), try план([а, б], байты: 8),
            try план([а, б], физическая: String(repeating: "f", count: 64)), try план([а, б], собственная: String(repeating: "f", count: 64)), try план([а, б], контекст: String(repeating: "f", count: 64))] {
            #expect(другой.хэшСостава != исходный.хэшСостава)
        }
    }
    @Test("Неверные метаданные и точные дубли отвергаются до разбиения")
    func неверныеВходы() {
        for вход in [[], [документ("a"), документ("a")], [документ("/a")], [документ("a", -1)], [документ("a", 33_554_433)], [документ("a", режим: "120000")],
            [.init(путь: "a", хэш: "bad", режим: "100644", размер: 1, класс: "отслеживаемый", объект: String(repeating: "1", count: 40))]] {
            #expect(throws: (any Error).self) { try план(вход) }
        }
        #expect(throws: (any Error).self) { try план([документ("a")], число: 257) }
        #expect(throws: (any Error).self) { try план([документ("a")], число: 0) }
        #expect(throws: (any Error).self) { try план([документ("a")], байты: 16_777_217) }
        #expect(throws: (any Error).self) { try план([документ("a")], опора: "bad") }
        #expect(throws: (any Error).self) { try план((0..<5).map { документ("d\($0)", 33_554_432) }) }
        #expect(throws: (any Error).self) { try план([.init(путь: "a", хэш: String(repeating: "1", count: 64), режим: "100644", размер: 1, класс: "отслеживаемый", объект: nil)]) }
        #expect(throws: (any Error).self) { try план([.init(путь: "a", хэш: String(repeating: "1", count: 64), режим: "100644", размер: 1, класс: "отслеживаемыи\u{306}", объект: String(repeating: "1", count: 40))]) }
    }
    @Test("5005 пустых документов дают двадцать порций, без нулевого продвижения")
    func двадцатьПорций() throws {
        let р = try план((0..<5005).map { документ("d\($0)", 0) })
        #expect(р.шаги.count == 20 && р.шаги.first?.начало == 0 && р.шаги.last?.конец == 5005)
        #expect(р.шаги.allSatisfy { $0.конец > $0.начало && $0.конец - $0.начало <= 256 && $0.допускаетОбход })
    }
    @Test("Oversized в начале, конце и подряд не создаёт дыр и пустых диапазонов")
    func смежностьНеизвестных() throws {
        for размеры in [[6, 1, 6], [6, 6, 6]] {
            let р = try план(размеры.enumerated().map { документ("d\($0.offset)", $0.element) }, байты: 5)
            #expect(р.шаги.flatMap { Array($0.начало..<$0.конец) } == Array(0..<размеры.count))
            #expect(р.шаги.first?.начало == 0 && р.шаги.last?.конец == размеры.count)
            #expect(zip(р.шаги, р.шаги.dropFirst()).allSatisfy { $0.конец == $1.начало })
            #expect(р.шаги.filter { !$0.допускаетОбход }.count == размеры.filter { $0 > 5 }.count)
        }
    }
    @Test("Ожидаемая запись сохраняет исходный номер и метаданные после изменения массива вызывающей стороны")
    func неизменяемаяЗапись() throws {
        var входы = [документ("a"), документ("b")]
        let р = try план(входы)
        входы[0] = документ("changed")
        let запись = try р.ожидаемаяЗапись(0)
        #expect(запись.номер == 0 && запись.документ.путь == "a" && запись.хэшПлана == р.хэшСостава)
        #expect(запись.опоры.контекст == String(repeating: "d", count: 64) && входы[0].путь == "changed")
        #expect(throws: (any Error).self) { try р.ожидаемаяЗапись(-1) }
        #expect(throws: (any Error).self) { try р.ожидаемаяЗапись(2) }
    }
}

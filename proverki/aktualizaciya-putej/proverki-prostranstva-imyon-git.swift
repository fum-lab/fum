            _ = try фикстуры.гит(корень, ["add", "--all"]); _ = try фикстуры.гит(корень, ["commit", "--quiet", "-m", "fixture tree sort"])
            let новая = try фикстуры.новаяОснова(корень, основа), индекс = try фикстуры.гит(корень, ["ls-files", "--stage", "-z"])

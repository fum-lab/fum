    @Test("Git tree с case-алиасами сохраняется как metadata плюс явное препятствие")
    func алиасыНеСхлопываются() async throws {
        try await фикстуры.фикстура { корень, _ in
            let объект = String(decoding: try фикстуры.гит(корень, ["rev-parse", "HEAD:Инструменты/X/SKILL.md"]), as: UTF8.self).trimmingCharacters(in: .newlines)
            for путь in ["A", "a"] {
                _ = try фикстуры.гит(корень, ["-c", "core.ignorecase=false", "update-index", "--add", "--cacheinfo", "100644,\(объект),\(путь)"])
            }
            let oid = String(decoding: try фикстуры.гит(корень, ["write-tree"]), as: UTF8.self).trimmingCharacters(in: .newlines)
            let индекс = try фикстуры.гит(корень, ["ls-files", "--stage", "-z"])
            let итог = try ПространствоИмёнGit.проверить(переченьДерева: фикстуры.гит(корень, ["ls-tree", "-rz", oid]), индекс: индекс, ожидаемоеДерево: oid, ожидаемыйХэшИндекса: хэшПутей(индекс))
            #expect(итог.листья.contains { $0.путь == Data("A".utf8) } && итог.листья.contains { $0.путь == Data("a".utf8) })
            #expect(итог.коллизии.contains { $0.пути.map { Data($0.utf8) } == [Data("A".utf8), Data("a".utf8)] })
            #expect(!итог.файловаяСистемаПроверена && !итог.применениеРазрешено)
        }
    }


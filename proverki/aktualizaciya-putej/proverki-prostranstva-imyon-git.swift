    @Test("NFD, symlink и gitlink сохраняют отдельные типы без чтения содержимого")
    func типыИФизическаяГраница() async throws {
        try await фикстуры.фикстура { корень, основа in
            let nfd = "docs/e\u{301}/x.md"
            try фикстуры.файл(корень, nfd)
            try FileManager.default.createSymbolicLink(atPath: корень.appendingPathComponent("link").path, withDestinationPath: "Инструменты/X/SKILL.md")
            _ = try фикстуры.гит(корень, ["-c", "core.precomposeunicode=false", "add", "--all"])
            _ = try фикстуры.гит(корень, ["update-index", "--add", "--cacheinfo", "160000,\(основа.коммит),external"])
            _ = try фикстуры.гит(корень, ["commit", "--quiet", "-m", "fixture namespace"])
            let новая = try фикстуры.новаяОснова(корень, основа), дерево = try фикстуры.гит(корень, ["ls-tree", "-rz", "HEAD"]), индекс = try фикстуры.гит(корень, ["ls-files", "--stage", "-z"])
            let итог = try ПространствоИмёнGit.проверить(переченьДерева: дерево, индекс: индекс, ожидаемоеДерево: новая.дерево, ожидаемыйХэшИндекса: хэшПутей(индекс))
            #expect(итог.листья.contains { $0.путь == Data(nfd.utf8) })
            #expect(итог.листья.contains { $0.путь == Data("link".utf8) && $0.вид == .символическаяСсылка })
            #expect(итог.листья.contains { $0.путь == Data("external".utf8) && $0.вид == .внешняяЗависимость })
            #expect(итог.каталоги.contains(Data("docs".utf8)) && итог.каталоги.contains(Data("docs/e\u{301}".utf8)))
            #expect(!итог.содержимоеОбъектовПроверено && !итог.файловаяСистемаПроверена && !итог.применениеРазрешено)
        }
    }

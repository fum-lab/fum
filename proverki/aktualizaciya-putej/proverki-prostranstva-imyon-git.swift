    @Test("Бюджет префиксов считает raw и folded байты только для новых точных префиксов")
    func пределПрефиксов() throws {
        let листья = ["a/b", "a/c"].map { ЛистДереваGit(путь: Data($0.utf8), режим: "100644", объект: String(repeating: "1", count: 40), вид: .файл) }
        // a: 1+1; a/b и a/c: по 3+3. Общий a повторно не считается.
        #expect(try ПространствоИмёнGit.вычислитьДерево(листья, пределБайтовПрефиксов: 14) == ПространствоИмёнGit.вычислитьДерево(листья))
        #expect(throws: (any Error).self) { try ПространствоИмёнGit.вычислитьДерево(листья, пределБайтовПрефиксов: 13) }
        #expect(throws: (any Error).self) { try ПространствоИмёнGit.вычислитьДерево(листья, пределБайтовПрефиксов: 67_108_865) }
        #expect(throws: (any Error).self) { try ПространствоИмёнGit.вычислитьДерево([], пределБайтовПрефиксов: -1) }
    }

            _ = try фикстуры.гит(корень, ["-c", "core.precomposeunicode=false", "add", "--all"])
            _ = try фикстуры.гит(корень, ["commit", "--quiet", "-m", "fixture alias"])
            let новая = try фикстуры.новаяОснова(корень, основа)
            let свой = try снимок.источник(корень, новая, файлы: [["path": алиас, "sha256": хэшПутей(Data("x".utf8)), "bytes": 1]])

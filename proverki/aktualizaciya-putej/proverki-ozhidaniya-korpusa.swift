@Suite("Независимое ожидание корпуса из закреплённых Git-объектов")
struct ПроверкиОжиданияКорпуса {
    let фикстуры = ПроверкиИнвентаряОбщейМиграции()
    let снимок = ПроверкиСнимкаКорпуса()

    func объект(_ данные: Data) -> String {
        Insecure.SHA1.hash(data: Data("blob \(данные.count)\0".utf8) + данные).map { String(format: "%02x", $0) }.joined()
    }

    @Test("Batch различает тело, LF и EOF, ограничивает размер до чтения тела")
    func обрамлениеИПределы() throws {
        let тело = Data([0, 10, 255, 120]), имя = объект(тело)
        let ответ = Data("\(имя) blob 4\n".utf8) + тело + Data([10])
        var смещение = 0, запросы: [Data] = [], завершён = false
        let результат = try ПротоколОбъектовКорпуса.прочитать(повторы: [имя: 2], занято: 0,
            записать: { запросы.append($0) }, прочитать: { размер in
                let конец = min(ответ.count, смещение + размер); defer { смещение = конец }
                return ответ.subdata(in: смещение..<конец)
            }, закончить: { завершён = true })
        #expect(результат[имя]?.хэш == хэшПутей(тело) && результат[имя]?.размер == 4)
        #expect(запросы == [Data((имя + "\n").utf8)] && завершён && смещение == ответ.count)
        let заголовки = ["\(имя) missing\n", "\(имя) blob 33554433\n", "\(имя) blob 2097152\n", "\(имя) blob -1\n", "\(имя) tree 4\n"]
        var неверные: [Data] = заголовки.map { Data($0.utf8) }
        неверные.append(Data("\(String(repeating: "0", count: 40)) blob 4\n".utf8) + тело + Data([10]))
        неверные.append(Data("\(имя) blob 4\n".utf8) + тело + Data([0]))
        неверные.append(ответ + Data([0])); неверные.append(Data(ответ.dropLast(2))); неверные.append(Data(repeating: 120, count: 128))
        неверные.append(Data("\(имя) blob 4\n".utf8) + Data([0, 10, 255, 121]) + Data([10]))
        for (номер, неверный) in неверные.enumerated() {
            var позиция = 0, запрошеноТело = false
            #expect(throws: (any Error).self) {
                try ПротоколОбъектовКорпуса.прочитать(повторы: [имя: 128], занято: 0, записать: { _ in }, прочитать: { размер in
                    if размер > 1 { запрошеноТело = true }
                    let конец = min(неверный.count, позиция + размер); defer { позиция = конец }
                    return Data(неверный).subdata(in: позиция..<конец)
                }, закончить: {})
            }
            if номер == 1 || номер == 2 { #expect(!запрошеноТело) }
        }
        let пустое = Data(), пустойОбъект = объект(пустое)
        let тела = [имя: тело, пустойОбъект: пустое], порядок = тела.keys.sorted()
        let ответы = порядок.map { Data("\($0) blob \(тела[$0]!.count)\n".utf8) + тела[$0]! + Data([10]) }
        let поток = ответы.reduce(into: Data()) { $0.append($1) }
        var позиция = 0, номер = 0, ожидаемаяГраница = 0
        let пара = try ПротоколОбъектовКорпуса.прочитать(повторы: [имя: 1, пустойОбъект: 1], занято: 0, записать: { запрос in
            #expect(позиция == ожидаемаяГраница && запрос == Data((порядок[номер] + "\n").utf8))
            ожидаемаяГраница += ответы[номер].count; номер += 1
        }, прочитать: { размер in
            let конец = min(поток.count, позиция + размер); defer { позиция = конец }
            return поток.subdata(in: позиция..<конец)
        }, закончить: {})
        #expect(номер == 2 && пара[пустойОбъект]?.размер == 0 && пара[имя]?.хэш == хэшПутей(тело))
        let единица = Data([120]), еёОбъект = объект(единица), заголовок = Data("\(еёОбъект) blob 1\n".utf8)
        let сБюджетом = заголовок + единица + Data([10]); var прочитано = 0, закончен = false
        #expect(throws: (any Error).self) {
            try ПротоколОбъектовКорпуса.прочитать(повторы: [еёОбъект: 2], занято: 134_217_727, записать: { _ in }, прочитать: { размер in
                let конец = min(сБюджетом.count, прочитано + размер); defer { прочитано = конец }
                return сБюджетом.subdata(in: прочитано..<конец)
            }, закончить: { закончен = true })
        }
        #expect(прочитано == заголовок.count && !закончен)
    }

    @Test("Ожидаемые байты берутся из Git и не следуют за изменённой ФС")
    func независимыйGit() async throws {
        try await фикстуры.фикстура { корень, основа in
            let свой = try снимок.источник(корень, основа)
            try фикстуры.файл(корень, "Инструменты/X/SKILL.md", "изменённые байты")
            let ожидание = try СоставительОжиданияКорпуса.составить(корень: корень, основа: основа, собственныйИсточник: свой, ожидаемыйХэшИсточника: хэшПутей(свой))
            try #require(ожидание.документы.count == 1)
            #expect(ожидание.документы.first?.хэш == хэшПутей(Data("x".utf8)))
            #expect(ожидание.документы.first?.размер == 1)
            #expect(throws: (any Error).self) {
                try ЧитательДокументовКорпуса.снять(корень: корень, ожидание: байтыПлана(ожидание), собственныйИсточник: свой)
            }
        }
    }

    @Test("Собственный вход принимается по внешнему pin; незаявленный Markdown закрывает состав")
    func опораИНеизвестныйФайл() async throws {
        try await фикстуры.фикстура { корень, основа in
            let свой = try снимок.источник(корень, основа)
            #expect(throws: (any Error).self) {
                try СоставительОжиданияКорпуса.составить(корень: корень, основа: основа, собственныйИсточник: свой, ожидаемыйХэшИсточника: String(repeating: "0", count: 64))
            }
            let отсутствующий = try снимок.источник(корень, основа, файлы: [["path": "absent.md", "sha256": хэшПутей(Data()), "bytes": 0]])
            #expect(throws: (any Error).self) {
                try СоставительОжиданияКорпуса.составить(корень: корень, основа: основа, собственныйИсточник: отсутствующий, ожидаемыйХэшИсточника: хэшПутей(отсутствующий))
            }
            try фикстуры.файл(корень, "unknown.md")
            #expect(throws: (any Error).self) {
                try СоставительОжиданияКорпуса.составить(корень: корень, основа: основа, собственныйИсточник: свой, ожидаемыйХэшИсточника: хэшПутей(свой))
            }
        }
    }

    @Test("Заявленный собственный файл включается по отдельной опоре; поздний HEAD/ref закрывает результат")
    func собственныйИПоздняяОснова() async throws {
        try await фикстуры.фикстура { корень, основа in
            try фикстуры.файл(корень, "own.md", "own")
            let свой = try снимок.источник(корень, основа, файлы: [["path": "own.md", "sha256": хэшПутей(Data("own".utf8)), "bytes": 3, "mode": "100644"]])
            let результат = try СоставительОжиданияКорпуса.составить(корень: корень, основа: основа, собственныйИсточник: свой, ожидаемыйХэшИсточника: хэшПутей(свой))
            #expect(результат.документы.count == 2)
            #expect(результат.документы.contains { $0.путь == "own.md" && $0.объект == nil && $0.класс == "собственный-неотслеживаемый" })
            _ = try фикстуры.гит(корень, ["update-ref", "refs/heads/fixture-late", основа.коммит])
            #expect(throws: (any Error).self) {
                try СоставительОжиданияКорпуса.составить(корень: корень, основа: основа, собственныйИсточник: свой, ожидаемыйХэшИсточника: хэшПутей(свой),
                    передФинальнойСверкойДляПроверки: { _ = try фикстуры.гит(корень, ["symbolic-ref", "HEAD", "refs/heads/fixture-late"]) })
            }
        }
    }

    @Test("Локальный replace не подменяет закреплённые байты Git-объекта")
    func безПодменыОбъекта() async throws {
        try await фикстуры.фикстура { корень, основа in
            try фикстуры.файл(корень, "replacement.txt", "replacement")
            let замена = String(decoding: try фикстуры.гит(корень, ["hash-object", "-w", "replacement.txt"]), as: UTF8.self).trimmingCharacters(in: .newlines)
            let исходный = объект(Data("x".utf8))
            _ = try фикстуры.гит(корень, ["replace", исходный, замена])
            #expect(try фикстуры.гит(корень, ["cat-file", "blob", исходный]) == Data("replacement".utf8))
            let свой = try снимок.источник(корень, основа)
            let ожидание = try СоставительОжиданияКорпуса.составить(корень: корень, основа: основа, собственныйИсточник: свой, ожидаемыйХэшИсточника: хэшПутей(свой))
            #expect(ожидание.документы.first?.объект == исходный && ожидание.документы.first?.хэш == хэшПутей(Data("x".utf8)))
        }
    }

    @Test("NFC-алиас отслеживаемого NFD не превращается в собственный второй документ")
    func алиасНеСобственный() async throws {
        try await фикстуры.фикстура { корень, основа in
            let путь = "Инструменты/e\u{301}/doc.md", алиас = путь.precomposedStringWithCanonicalMapping

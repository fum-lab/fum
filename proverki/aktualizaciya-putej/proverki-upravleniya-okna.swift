@Suite("Связь управляющих полей с переданными raw bytes без подтверждения процесса")
struct ПроверкиУправленияОкна {
    let основа = ПроверкиОконКандидатов()
    struct Вход {
        let план: ПланПорцийКандидатов
        let намерение: НамерениеОкнаДиагностики
        let байтыНамерения: Data
        let артефактНамерения: АртефактКандидатов
        let терминал: ТерминалОкнаДиагностики
        let байтыТерминала: Data
        let манифест: МанифестОкнаДиагностики
        let байтыМанифеста: Data
        let артефактМанифеста: АртефактКандидатов
        let учёт: УчтённаяКоллекцияКандидатов
    }
    func вход(голова: ГоловаПроверенногоОкна? = nil) throws -> Вход {
        let п = try основа.план(), в = try основа.вход(п, начало: голова?.окно.следующаяПорция ?? 0, голова: голова), м = в.манифест
        let н = НамерениеОкнаДиагностики(окно: м.окно, опоры: м.опоры, хэшПлана: м.хэшПлана, хэшПредыдущейТочки: м.хэшПредыдущейТочки,
            перваяПорция: м.перваяПорция, числоПорций: м.числоПорций)
        let каталог = "runs/r\(м.перваяПорция)/"
        let бн = try СвязываниеУправленияОкна.байтыНамерения(н), фн = основа.файл(каталог + "intent.json", байты: бн)
        let новый = МанифестОкнаДиагностики(окно: м.окно, опоры: м.опоры, хэшПлана: м.хэшПлана, хэшНамерения: фн.хэш,
            хэшПредыдущейТочки: м.хэшПредыдущейТочки, перваяПорция: м.перваяПорция, числоПорций: м.числоПорций, результаты: м.результаты)
        let бм = try ПроверкаОкнаКандидатов.байтыМанифеста(новый), фм = основа.файл(каталог + "manifest.json", байты: бм)
        let черновик = ТерминалОкнаДиагностики(окно: м.окно, опоры: м.опоры, кодВыхода: 0, хэшМанифеста: фм.хэш, хэшНамерения: фн.хэш,
            артефакт: основа.файл(каталог + "terminal.json"))
        let бт = try СвязываниеУправленияОкна.байтыТерминала(черновик), фт = основа.файл(каталог + "terminal.json", байты: бт)
        let т = ТерминалОкнаДиагностики(окно: черновик.окно, опоры: черновик.опоры, кодВыхода: 0, хэшМанифеста: фм.хэш, хэшНамерения: фн.хэш, артефакт: фт)
        let у = try УчётАртефактовКандидатов.создать(идентификатор: основа.опоры.коллекция, хэшПрофиля: основа.опоры.хэшПрофиля,
            артефакты: (голова?.учёт.артефакты ?? []) + [фн, фм, фт] + новый.результаты.map(\.артефакт))
        return .init(план: п, намерение: н, байтыНамерения: бн, артефактНамерения: фн, терминал: т, байтыТерминала: бт,
            манифест: новый, байтыМанифеста: бм, артефактМанифеста: фм, учёт: у)
    }
    func связать(_ в: Вход, намерение: НамерениеОкнаДиагностики? = nil, байтыНамерения: Data? = nil,
        терминал: ТерминалОкнаДиагностики? = nil, байтыТерминала: Data? = nil, учёт: УчтённаяКоллекцияКандидатов? = nil) throws -> СвязанноеУправлениеОкна {
        try СвязываниеУправленияОкна.связать(намерение: намерение ?? в.намерение, байтыНамерения: байтыНамерения ?? в.байтыНамерения,
            артефактНамерения: в.артефактНамерения, терминал: терминал ?? в.терминал, байтыТерминала: байтыТерминала ?? в.байтыТерминала,
            манифест: в.манифест, байтыМанифеста: в.байтыМанифеста, артефактМанифеста: в.артефактМанифеста, учёт: учёт ?? в.учёт)
    }
    @Test("Канонические три файла связываются, но не доказывают OS/FS или право запуска")
    func каноническаяСвязь() throws {
        let в = try вход(), у = try связать(в)
        let р = try СвязываниеУправленияОкна.проверитьОкно(план: в.план, опоры: основа.опоры, предыдущая: .начало,
            управление: [.связанное(у)], учёт: в.учёт, манифест: в.манифест, байтыМанифеста: в.байтыМанифеста, артефактМанифеста: в.артефактМанифеста)
        #expect(у.каноническиеУправляющиеБайтыПроверены && р.каноническиеУправляющиеБайтыПроверены && р.окно.следующийДокумент == 1)
        #expect(!р.физическиеФайлыПроверены && !р.терминальныйПроцессПроверен && !р.текущаяГоловаПроверена
            && !р.внешняяИсторияПроверена && !р.запускРазрешён && !р.продолжениеРазрешено && !р.применениеРазрешено)
    }
    @Test("Пропущенный LF, дополнительный хвост и сверхпредел закрываются")
    func точныеБайты() throws {
        let в = try вход()
        for б in [Data(в.байтыНамерения.dropLast()), в.байтыНамерения + Data([32]), Data(repeating: 32, count: 16_385)] {
            #expect(throws: (any Error).self) { try связать(в, байтыНамерения: б) }
        }
        for б in [Data(в.байтыТерминала.dropLast()), в.байтыТерминала + Data([32]), Data(repeating: 32, count: 16_385)] {
            #expect(throws: (any Error).self) { try связать(в, байтыТерминала: б) }
        }
    }
    @Test("Изменённый frontier намерения не маскируется согласованными raw bytes")
    func чужоеНамерение() throws {
        let в = try вход(), н = в.намерение
        let иной = НамерениеОкнаДиагностики(окно: н.окно, опоры: н.опоры, хэшПлана: н.хэшПлана,
            хэшПредыдущейТочки: nil, перваяПорция: 1, числоПорций: 1)
        #expect(throws: (any Error).self) { try связать(в, намерение: иной, байтыНамерения: СвязываниеУправленияОкна.байтыНамерения(иной)) }
    }
    @Test("Одинаковые поля не заменяют точную роль и присутствие управляющего файла")
    func учётУправления() throws {
        let в = try вход()
        let у = try УчётАртефактовКандидатов.создать(идентификатор: основа.опоры.коллекция, хэшПрофиля: основа.опоры.хэшПрофиля,
            артефакты: в.учёт.артефакты.filter { $0.путь != в.терминал.артефакт.путь })
        #expect(throws: (any Error).self) { try связать(в, учёт: у) }
    }
    @Test("Пересчитанный SHA сырых terminal exit1 не подтверждает typed exit0")
    func подменаВыхода() throws {
        let в = try вход(), т = в.терминал
        let отказ = ТерминалОкнаДиагностики(окно: т.окно, опоры: т.опоры, кодВыхода: 1,
            хэшМанифеста: т.хэшМанифеста, хэшНамерения: т.хэшНамерения, артефакт: т.артефакт)
        let сырые = try СвязываниеУправленияОкна.байтыТерминала(отказ), ф = основа.файл(т.артефакт.путь, байты: сырые)
        let ложный = ТерминалОкнаДиагностики(окно: т.окно, опоры: т.опоры, кодВыхода: 0,
            хэшМанифеста: т.хэшМанифеста, хэшНамерения: т.хэшНамерения, артефакт: ф)
        let у = try УчётАртефактовКандидатов.создать(идентификатор: основа.опоры.коллекция, хэшПрофиля: основа.опоры.хэшПрофиля,
            артефакты: в.учёт.артефакты.filter { $0.путь != ф.путь } + [ф])
        #expect(throws: ОтказСсылокПакета.условие("дрейф-канонических-байтов-управления")) { try связать(в, терминал: ложный, байтыТерминала: сырые, учёт: у) }
    }
    @Test("Несвязанная попытка остаётся блокирующей в общем списке")
    func несвязаннаяИстория() throws {
        let в = try вход(), у = try связать(в)
        let неизвестная = ПопыткаОкнаДиагностики(окно: "00000000-0000-4000-8000-000000000999", намерение: основа.файл("unknown/intent"), терминал: .ожидается)
        #expect(throws: ОтказСсылокПакета.условие("несвязанная-попытка-блокирует-историю")) {
            try СвязываниеУправленияОкна.проверитьОкно(план: в.план, опоры: основа.опоры, предыдущая: .начало,
                управление: [.несвязанное(неизвестная), .связанное(у)], учёт: в.учёт, манифест: в.манифест,
                байтыМанифеста: в.байтыМанифеста, артефактМанифеста: в.артефактМанифеста)
        }
    }
    @Test("Собственный descriptor терминала не создаёт самоссылку в его байтах")
    func нетСамоссылки() throws {
        let в = try вход(), т = в.терминал
        let другой = ТерминалОкнаДиагностики(окно: т.окно, опоры: т.опоры, кодВыхода: т.кодВыхода,
            хэшМанифеста: т.хэшМанифеста, хэшНамерения: т.хэшНамерения, артефакт: основа.файл("other/terminal"))
        let байты = try СвязываниеУправленияОкна.байтыТерминала(другой)
        #expect(байты == в.байтыТерминала && байты.last == 10)
    }
    @Test("Пересчитанные SHA лишнего и повторного поля не обходят закрытую каноническую форму")
    func лишниеПоля() throws {
        let в = try вход(), т = в.терминал, текст = String(decoding: в.байтыТерминала, as: UTF8.self)
        for вставка in ["  \"кодОбычногоВыхода\": 0,\n", "  \"постороннееПоле\": true,\n"] {
            let сырые = Data(текст.replacingOccurrences(of: "{\n", with: "{\n" + вставка).utf8)
            let ф = основа.файл(т.артефакт.путь, байты: сырые)
            let другой = ТерминалОкнаДиагностики(окно: т.окно, опоры: т.опоры, кодВыхода: 0,
                хэшМанифеста: т.хэшМанифеста, хэшНамерения: т.хэшНамерения, артефакт: ф)
            let у = try УчётАртефактовКандидатов.создать(идентификатор: основа.опоры.коллекция, хэшПрофиля: основа.опоры.хэшПрофиля,
                артефакты: в.учёт.артефакты.filter { $0.путь != ф.путь } + [ф])
            #expect(throws: ОтказСсылокПакета.условие("дрейф-канонических-байтов-управления")) { try связать(в, терминал: другой, байтыТерминала: сырые, учёт: у) }
        }
    }
    @Test("Размер и путь control ref проверяются по фактическим байтам до построения token")
    func метаданныеСсылки() throws {
        let в = try вход(), т = в.терминал
        let ф = АртефактКандидатов(путь: т.артефакт.путь, хэш: т.артефакт.хэш, размер: т.артефакт.размер - 1, роль: .управление)
        let другой = ТерминалОкнаДиагностики(окно: т.окно, опоры: т.опоры, кодВыхода: 0,
            хэшМанифеста: т.хэшМанифеста, хэшНамерения: т.хэшНамерения, артефакт: ф)
        let у = try УчётАртефактовКандидатов.создать(идентификатор: основа.опоры.коллекция, хэшПрофиля: основа.опоры.хэшПрофиля,
            артефакты: в.учёт.артефакты.filter { $0.путь != ф.путь } + [ф])
        #expect(throws: ОтказСсылокПакета.условие("дрейф-канонических-байтов-управления")) { try связать(в, терминал: другой, учёт: у) }
        let длинная = АртефактКандидатов(путь: String(repeating: "a", count: 1025), хэш: ф.хэш, размер: ф.размер, роль: .управление)
        let неверный = ТерминалОкнаДиагностики(окно: т.окно, опоры: т.опоры, кодВыхода: 0,
            хэшМанифеста: т.хэшМанифеста, хэшНамерения: т.хэшНамерения, артефакт: длинная)
        #expect(throws: ОшибкаПутей.self) { try связать(в, терминал: неверный) }
    }
    @Test("Связанный canonical exit1 сохраняется как факт и блокирует успешное окно")
    func отказПроизводителя() throws {
        let в = try вход(), т = в.терминал
        let черновик = ТерминалОкнаДиагностики(окно: т.окно, опоры: т.опоры, кодВыхода: 1,
            хэшМанифеста: т.хэшМанифеста, хэшНамерения: т.хэшНамерения, артефакт: т.артефакт)
        let байты = try СвязываниеУправленияОкна.байтыТерминала(черновик), ф = основа.файл(т.артефакт.путь, байты: байты)
        let отказ = ТерминалОкнаДиагностики(окно: т.окно, опоры: т.опоры, кодВыхода: 1,
            хэшМанифеста: т.хэшМанифеста, хэшНамерения: т.хэшНамерения, артефакт: ф)
        let у = try УчётАртефактовКандидатов.создать(идентификатор: основа.опоры.коллекция, хэшПрофиля: основа.опоры.хэшПрофиля,
            артефакты: в.учёт.артефакты.filter { $0.путь != ф.путь } + [ф])
        let связь = try связать(в, терминал: отказ, байтыТерминала: байты, учёт: у)
        #expect(throws: ОтказСсылокПакета.условие("неверный-терминал-окна")) {
            try СвязываниеУправленияОкна.проверитьОкно(план: в.план, опоры: основа.опоры, предыдущая: .начало,
                управление: [.связанное(связь)], учёт: у, манифест: в.манифест, байтыМанифеста: в.байтыМанифеста, артефактМанифеста: в.артефактМанифеста)
        }
    }
    @Test("Вторая порция сохраняет все raw-bound tokens, ledger и закреплённую голову")
    func связанноеПродолжение() throws {
        let а = try вход(), связьА = try связать(а)
        let первое = try СвязываниеУправленияОкна.проверитьОкно(план: а.план, опоры: основа.опоры, предыдущая: .начало,
            управление: [.связанное(связьА)], учёт: а.учёт, манифест: а.манифест, байтыМанифеста: а.байтыМанифеста, артефактМанифеста: а.артефактМанифеста)
        let г = try основа.голова(первое.окно), б = try вход(голова: г), связьБ = try связать(б)
        let второе = try СвязываниеУправленияОкна.проверитьОкно(план: б.план, опоры: основа.опоры, предыдущая: .голова(г),
            управление: [.связанное(связьА), .связанное(связьБ)], учёт: б.учёт, манифест: б.манифест, байтыМанифеста: б.байтыМанифеста, артефактМанифеста: б.артефактМанифеста)
        #expect(второе.окно.следующаяПорция == 2 && второе.окно.следующийДокумент == 2 && второе.каноническиеУправляющиеБайтыПроверены)
        #expect(throws: (any Error).self) {
            try СвязываниеУправленияОкна.проверитьОкно(план: б.план, опоры: основа.опоры, предыдущая: .голова(г),
                управление: [.связанное(связьБ), .связанное(связьА)], учёт: б.учёт, манифест: б.манифест, байтыМанифеста: б.байтыМанифеста, артефактМанифеста: б.артефактМанифеста)
        }
    }
}

    @Test("Одинаковые байты не заменяют точный путь документа и контекст")
    func привязкаНеПоОдномуХэшуТела() throws {
        let д = вход("same body"), другойПуть = вход("same body", путь: "own.md"), к = try контекст()
        let первыйПакет = try пакет(д, к), другойПакет = try пакет(другойПуть, к)
        #expect(д.sha256 == другойПуть.sha256 && первыйПакет != другойПакет)
        let ф = ПроверкиКандидатовАдресов(), узлы = [ф.цель("docs", .каталог), ф.цель("docs/x.md"), ф.цель("docs/secret-target")]
        let другойКонтекст = try ф.контекст(узлы, узлы, опора: String(repeating: "2", count: 64))
        let пакетДругогоКонтекста = try пакет(д, другойКонтекст)
        #expect(первыйПакет != пакетДругогоКонтекста)
    }

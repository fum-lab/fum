@Suite("Пакет связанных результатов разметки и адресов без исходных строк")
struct ПроверкиПакетаКандидатов {
    func вход(_ текст: String, путь: String = "docs/x.md") -> ДокументСсылокПакета { ПроверкиПеречняАдресов().документ(текст, путь: путь) }
    func контекст() throws -> КонтекстКандидатовАдресов {
        let ф = ПроверкиКандидатовАдресов()
        return try ф.контекст([ф.цель("docs", .каталог), ф.цель("docs/x.md"), ф.цель("docs/secret-target")],
            [ф.цель("docs", .каталог), ф.цель("docs/x.md"), ф.цель("docs/secret-target")])
    }
    func запись(_ документ: ДокументСсылокПакета, _ контекст: КонтекстКандидатовАдресов) throws -> ОжидаемаяЗаписьПорции {
        let метаданные = ДокументПланаПорций(путь: документ.путь, хэш: документ.sha256, режим: "100644", размер: документ.байты.count, класс: "отслеживаемый", объект: String(repeating: "1", count: 40))
        return try ПланировщикПорцийКандидатов.построить([метаданные], хэшОжидания: String(repeating: "a", count: 64),
            хэшФизическогоСнимка: String(repeating: "b", count: 64), хэшСобственногоИсточника: String(repeating: "c", count: 64), хэшКонтекста: контекст.хэшСостава).ожидаемаяЗапись(0)
    }
    func пакет(_ документ: ДокументСсылокПакета, _ контекст: КонтекстКандидатовАдресов, предел: Int = 33_554_432) throws -> Data {
        let перечень = РешательСсылокПакета.перечислитьАдреса(документ)
        let кандидаты = РешательСсылокПакета.диагностироватьРазрешение(документ, перечень: перечень, контекст: контекст, ожидаемыйХэшКонтекста: контекст.хэшСостава)
        return try УпаковщикКандидатовАдресов.упаковать(документ, ожидаемая: запись(документ, контекст), перечень: перечень, кандидаты: кандидаты, пределВыхода: предел)
    }
    @Test("Повторные упоминания сохраняются отдельно, source/query/labels не выводятся")
    func повторныеУпоминания() throws {
        let документ = вход("[ТАЙНАЯПОДПИСЬ][r] [r][] [r]\n[r]: secret-target?q=СЕКРЕТНЫЙЗАПРОС#якорь\n"), к = try контекст()
        let байты = try пакет(документ, к), текст = String(decoding: байты, as: UTF8.self)
        #expect(!текст.contains("ТАЙНАЯПОДПИСЬ") && !текст.contains("СЕКРЕТНЫЙЗАПРОС") && !текст.contains("secret-target") && !текст.contains("docs/x.md"))
        let объект = try #require(JSONSerialization.jsonObject(with: байты) as? [String: Any])
        #expect((объект["узлы"] as? [[Any]])?.count == 4)
        #expect((объект["вхождения"] as? [[Any]])?.count == 1 && (объект["упоминания"] as? [[Any]])?.count == 3)
        #expect(объект["применениеРазрешено"] as? Bool == false && байты.last == 10 && текст.contains("\n  \""))
    }
    @Test("Data slice и NFD/emoji/CRLF сохраняют исходные координаты")
    func логическиеДиапазоны() throws {
        let исходный = вход("Ё🙂 e\u{301} [x](secret-target)\r\n"), буфер = Data([1, 2, 3]) + исходный.байты
        let срез = ДокументСсылокПакета(путь: исходный.путь, байты: буфер.dropFirst(3), sha256: исходный.sha256), к = try контекст()
        #expect(try пакет(исходный, к) == пакет(срез, к))
    }
    @Test("Отсутствующий документ в tracked context сохраняет lexical nodes и UNKNOWN IDs")
    func собственныйДокумент() throws {
        let документ = вход("[x](secret-target) [r]\n[r]: secret-target\n", путь: "own.md"), байты = try пакет(документ, контекст())
        let объект = try #require(JSONSerialization.jsonObject(with: байты) as? [String: Any])
        #expect((объект["узлы"] as? [[Any]])?.count == 3)
        #expect((объект["неразобранныеУзлы"] as? [Int])?.count == 3 && объект["всеЗаявленныеУзлыУчтены"] as? Bool == false)
    }
    @Test("Запись другого ordinal/пути и исчерпанный output budget не принимаются")
    func чужаяЗаписьИПредел() throws {
        let д = вход("[x](secret-target)"), к = try контекст(), перечень = РешательСсылокПакета.перечислитьАдреса(д)
        let р = РешательСсылокПакета.диагностироватьРазрешение(д, перечень: перечень, контекст: к, ожидаемыйХэшКонтекста: к.хэшСостава)
        #expect(throws: (any Error).self) { try УпаковщикКандидатовАдресов.упаковать(д, ожидаемая: запись(вход("[x](secret-target)", путь: "other.md"), к), перечень: перечень, кандидаты: р) }
        #expect(throws: (any Error).self) { try пакет(д, к, предел: 1) }
    }
    func копия(_ р: КандидатыРазрешенияДокумента, упоминания: [УпоминаниеКандидатаАдреса]? = nil, ошибки: [String]? = nil) -> КандидатыРазрешенияДокумента {
        .init(путь: р.путь, хэшДокумента: р.хэшДокумента, хэшКонтекста: р.хэшКонтекста, вхождения: р.вхождения,
            упоминания: упоминания ?? р.упоминания, неразобранныеУзлы: р.неразобранныеУзлы, ошибки: ошибки ?? р.ошибки, всеЗаявленныеУзлыУчтены: р.всеЗаявленныеУзлыУчтены)
    }
    func копия(_ п: ПереченьАдресовДокумента, узлы: [УзелПеречняАдресов]) -> ПереченьАдресовДокумента {
        .init(путь: п.путь, заявленныйХэш: п.заявленныйХэш, размер: п.размер, хэшПроверен: п.хэшПроверен,
            обходЗавершён: п.обходЗавершён, синтаксисПолностьюРаспознан: п.синтаксисПолностьюРаспознан, узлы: узлы, ошибки: п.ошибки,
            неизвестныеДиапазоны: п.неизвестныеДиапазоны, скрытыеДиапазоны: п.скрытыеДиапазоны,
            эвристическиЗащищённыеДиапазоны: п.эвристическиЗащищённыеДиапазоны, неподдержанныеКонтейнеры: п.неподдержанныеКонтейнеры)
    }
    @Test("Неизвестная строка ошибки сохраняется только отпечатком")
    func ошибкаБезИсходногоТекста() throws {
        let д = вход("[x](secret-target)"), к = try контекст(), п = РешательСсылокПакета.перечислитьАдреса(д)
        let р = РешательСсылокПакета.диагностироватьРазрешение(д, перечень: п, контекст: к, ожидаемыйХэшКонтекста: к.хэшСостава)
        let тайна = "НЕПЕЧАТАТЬ?token=тайный-фрагмент"
        let б = try УпаковщикКандидатовАдресов.упаковать(д, ожидаемая: запись(д, к), перечень: п, кандидаты: копия(р, ошибки: [тайна]))
        #expect(!String(decoding: б, as: UTF8.self).contains(тайна))
        let о = try #require(JSONSerialization.jsonObject(with: б) as? [String: Any])
        let ошибка = try #require((о["ошибкиРазрешения"] as? [[Any]])?.first)
        #expect(ошибка[0] as? String == хэшПутей(Data(тайна.utf8)) && ошибка[1] as? Int == тайна.utf8.count)
    }
    @Test("Nil, пустой range и присутствующий пустой path различаются")
    func пустыеЗначения() throws {
        let д = вход("[x]()"), б = try пакет(д, контекст()), о = try #require(JSONSerialization.jsonObject(with: б) as? [String: Any])
        let узел = try #require((о["узлы"] as? [[Any]])?.first), событие = try #require((о["вхождения"] as? [[Any]])?.first)
        let адрес = try #require(узел[3] as? [Int])
        #expect(адрес.count == 2 && адрес[0] == адрес[1] && (узел[5] as? [Any])?.isEmpty == true)
        let пустойПуть = try #require(событие[11] as? [Any])
        #expect(пустойПуть[0] as? String == хэшПутей(Data()) && пустойПуть[1] as? Int == 0)
        #expect((событие[10] as? [Any])?.isEmpty == true)
    }
    @Test("Индекс вхождения не подменяется номером определения, разрыв кодировки закрывается")
    func индексыИДиапазоны() throws {
        let д = вход("Ё [r]\n[r]: secret-target\n"), к = try контекст(), п = РешательСсылокПакета.перечислитьАдреса(д)
        let р = РешательСсылокПакета.диагностироватьРазрешение(д, перечень: п, контекст: к, ожидаемыйХэшКонтекста: к.хэшСостава)
        let ссылка = try #require(р.упоминания.first)
        let неверная = УпоминаниеКандидатаАдреса(номерУзла: ссылка.номерУзла, определения: ссылка.определения, вхождение: р.вхождения.count, ошибка: nil)
        #expect(throws: ОтказСсылокПакета.условие("неверный-индекс-вхождения-пакета")) {
            try УпаковщикКандидатовАдресов.упаковать(д, ожидаемая: запись(д, к), перечень: п, кандидаты: копия(р, упоминания: [неверная]))
        }
        let первый = try #require(п.узлы.first)
        let разрыв = УзелПеречняАдресов(номер: 0, вид: первый.вид, целиком: 0..<д.байты.count, адрес: 1..<2,
            подпись: nil, метка: nil, ключМетки: nil, определения: первый.определения, изображение: false, эвристическиЗащищён: false, неподдержанныйКонтейнер: false)
        #expect(throws: ОтказСсылокПакета.условие("разрыв-кодировки-пакета")) {
            try УпаковщикКандидатовАдресов.упаковать(д, ожидаемая: запись(д, к), перечень: копия(п, узлы: [разрыв] + п.узлы.dropFirst()), кандидаты: р)
        }
    }
    @Test("Сумма перекрывающихся адресов ограничивается до хэширования")
    func повторноеХэширование() throws {
        let д = вход(String(repeating: "x", count: 256)), к = try контекст(), диапазон = 0..<д.байты.count
        let узлы = (0..<1000).map { УзелПеречняАдресов(номер: $0, вид: .встроенная, целиком: диапазон, адрес: диапазон,
            подпись: nil, метка: nil, ключМетки: nil, определения: [], изображение: false, эвристическиЗащищён: false, неподдержанныйКонтейнер: false) }
        let п = копия(РешательСсылокПакета.перечислитьАдреса(д), узлы: узлы)
        let события = (0..<1000).map { ВхождениеКандидатаАдреса(номерУзла: $0, адрес: диапазон, суффикс: диапазон.upperBound..<диапазон.upperBound,
            хэшАдреса: nil, хэшСуффикса: nil, вид: .отказ, прежняяЦель: nil, видПрежнейЦели: nil, будущаяЦель: nil, граница: nil, новыйПутьАдреса: nil, сохранёнИсходныйПуть: false, ошибка: nil) }
        let р = КандидатыРазрешенияДокумента(путь: д.путь, хэшДокумента: д.sha256, хэшКонтекста: к.хэшСостава,
            вхождения: события, упоминания: [], неразобранныеУзлы: [], ошибки: [], всеЗаявленныеУзлыУчтены: true)
        #expect(throws: ОтказСсылокПакета.условие("предел-хэширования-пакета")) {
            try УпаковщикКандидатовАдресов.упаковать(д, ожидаемая: запись(д, к), перечень: п, кандидаты: р, пределХэшируемыхБайтов: 2048)
        }
    }
    @Test("Форматированный emitter считает escaping и точный предел до buffer")
    func точныйВыход() throws {
        let строка = "x\n\"\0🙂e\u{301}", значение = ЗначениеПакета.объект([("сообщение", .строка(строка))])
        let б = try ФорматированныйПисательПакета.записать(значение, предел: 1024)
        #expect(try ФорматированныйПисательПакета.записать(значение, предел: б.count) == б)
        #expect(throws: (any Error).self) { try ФорматированныйПисательПакета.записать(значение, предел: б.count - 1) }
        #expect(throws: (any Error).self) { try ФорматированныйПисательПакета.записать(значение, предел: 33_554_433) }
        let о = try #require(JSONSerialization.jsonObject(with: б) as? [String: String])
        #expect(о["сообщение"].map { Data($0.utf8) } == Data(строка.utf8))
        #expect(throws: (any Error).self) { try ФорматированныйПисательПакета.записать(.объект([("a", .число(1)), ("a", .число(2))]), предел: 1024) }
        #expect(throws: ОтказСсылокПакета.условие("предел-ключа-пакета")) {
            try ФорматированныйПисательПакета.записать(.объект([(String(repeating: "x", count: 1025), .число(1))]), предел: 2048)
        }
    }

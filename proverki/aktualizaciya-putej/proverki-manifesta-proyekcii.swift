    @Test("Точный 27-MB Git-манифест остаётся историческим при stale README",
          .enabled(if: ProcessInfo.processInfo.environment["ФУМ_ИСТОРИЧЕСКИЙ_МАНИФЕСТ"] != nil))
    func адресныйМанифест() throws {
        let среда = ProcessInfo.processInfo.environment, путь = try #require(среда["ФУМ_ИСТОРИЧЕСКИЙ_МАНИФЕСТ"])
        let данные = try ПроверкиРазмещенияТекста().ограниченно(путь, предел: 33_554_432)
        let опора = ОпораИсторическогоМанифеста(коммит: "3e4ad89c49ef17fd6c377698f7828351aecfa051", путь: путьМанифеста,
            объект: "6b52eb9a715ce3981616c14ee1eadfcfe12dda46", хэш: "d228336a674201fdc20be36fa618566fc0eee512222e7b2c92bfeb60aa65d32d")
        let индекс = try ИсторическийМанифестПроекции.прочитать(данные, опора: опора)
        #expect(индекс.пары.count == 12_024)
        let путьОжидания = try #require(среда["ФУМ_ТЕКУЩЕЕ_ОЖИДАНИЕ_ПРОЕКЦИИ"]), хэшОжидания = try #require(среда["ФУМ_ХЭШ_ТЕКУЩЕГО_ОЖИДАНИЯ_ПРОЕКЦИИ"])
        let текущее = try ПроверкиРазмещенияТекста().ограниченно(путьОжидания, предел: 4_194_304)
        try #require(хэшПутей(текущее) == хэшОжидания)
        _ = try ТокеныJSONМиграции.разобрать(текущее)
        let модель = try JSONDecoder().decode(ОжиданиеСнимкаКорпуса.self, from: текущее)
        try #require(модель.основа.коммит == опора.коммит)
        let readme = try #require(модель.документы.first { Data($0.путь.utf8) == Data("README.md".utf8) })
        let историческая = try #require(индекс.найти(цель))
        #expect(историческая.хэшИсторическогоИсточника == "385ef4bd1613d2e9893543250400299db0961069c78b91f5871b0696f82db955" && историческая.хэшИсторическогоИсточника != readme.хэш)
        let итог = try #require(индекс.сверить(цель, хэшТекущегоИсточника: readme.хэш, режимТекущегоИсточника: readme.режим, размерТекущегоИсточника: readme.размер,
            хэшТекущейПроекции: nil, режимТекущейПроекции: nil, естьФрагмент: true))
        #expect(!итог.исходникСовпал && !итог.перенаправлениеРазрешено)
        if let выход = среда["ФУМ_РЕЗУЛЬТАТ_ИСТОРИЧЕСКОГО_МАНИФЕСТА"] {
            let результат: [String: Any] = ["схема": "fum.адресная-проверка-исторического-манифеста.1", "манифестRawSHA256": опора.хэш,
                "пары": индекс.пары.count, "узлыJSON": индекс.статистика.узлы, "объектыJSON": индекс.статистика.объекты,
                "глубинаJSON": индекс.статистика.глубина, "текущийREADMEСовпал": итог.исходникСовпал, "перенаправлениеРазрешено": false]
            try (JSONSerialization.data(withJSONObject: результат, options: [.prettyPrinted, .sortedKeys]) + Data([10])).write(to: URL(fileURLWithPath: выход), options: .withoutOverwriting)
        }
    }

@Suite("Отдельный ограниченный синтаксический профиль манифеста проекции")
struct ПроверкиМанифестаПроекции {
    let цель = "Proyekcii/Bratislavskaya-pamyatj/fajlyi/README.md"
    let путьМанифеста = "Proyekcii/Bratislavskaya-pamyatj/manifest-proiskhozhdeniya-v2.json"
    func фикстура(_ изменить: (inout [String: Any]) -> Void = { _ in }) throws -> (Data, ОпораИсторическогоМанифеста) {
        let хэш = "sha256:" + хэшПутей(Data("x".utf8))
        let запись: [String: Any] = ["исходный_путь": "README.md", "целевой_путь": цель, "компоненты_пути": [["исходный": "README.md", "целевая_основа": "README", "сохранённое_расширение": ".md", "целевой": "README.md", "изменён": false]],
            "тип": "обычный_файл", "режим": "100644", "размер_источника": 1, "хэш_источника": хэш, "хэш_цели": хэш, "класс_содержимого": "прочий_точный_формат", "действие_содержимого": "сохранить_байты", "причина_действия": "синтетический источник"]
        var корень: [String: Any] = ["схема": "fum.манифест-братиславской-проекции.2", "хэш_плана": "sha256:" + String(repeating: "a", count: 64), "хэш_политики": "sha256:" + String(repeating: "b", count: 64),
            "исходный_снимок": ["хэш_инвентаря": "sha256:" + String(repeating: "c", count: 64), "хэш_политики": "sha256:" + String(repeating: "b", count: 64)], "исходная_область": ".", "производное_пространство": "Proyekcii", "целевая_область": "Proyekcii/Bratislavskaya-pamyatj",
            "корень_файлов": "Proyekcii/Bratislavskaya-pamyatj/fajlyi", "путь_манифеста": путьМанифеста, "исключённые_префиксы": [".git", "Подузлы", "Proyekcii"], "преобразование": ["ревизия": "837e2ce107b97ee7b9d3344c9fe99142281fe393", "исходная_письменность": "Cyrl", "целевая_письменность": "Latn", "таблица": "ru", "метод": "applyingTransform"],
            "форматная_политика": [:], "пустые_каталоги": "не_включаются_в_инвентарь_репозитория", "записи": [запись], "итоговые_файлы": [цель, путьМанифеста].sorted(by: порядокПутей)]
        изменить(&корень)
        let данные = try JSONSerialization.data(withJSONObject: корень, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) + Data([10])
        let объект = Insecure.SHA1.hash(data: Data("blob \(данные.count)\0".utf8) + данные).map { String(format: "%02x", $0) }.joined()
        return (данные, .init(коммит: String(repeating: "1", count: 40), путь: путьМанифеста, объект: объект, хэш: хэшПутей(данные)))
    }
    @Test("Большой профиль не расширяет прежний 4-MiB профиль")
    func отдельныйПредел() throws {
        let данные = Data("{\"поле\":\"".utf8) + Data(repeating: 120, count: 4_194_304) + Data("\"}".utf8)
        #expect(throws: (any Error).self) { try ТокеныJSONМиграции.разобрать(данные) }
        let итог = try СинтаксисБольшогоМанифестаПроекции.проверить(данные)
        #expect(итог.байты == данные.count && итог.узлы == 2 && итог.объекты == 1 && итог.глубина == 1)
    }
    @Test("Ключи unescape-проверяются без хранения всех строк и диапазонов")
    func ключиИСтатистика() throws {
        let данные = Data(#"{"записи":[{"a/b":"строка","x":2},{}]}"#.utf8)
        var ключи: [String: Set<Data>] = [:]
        let итог = try СинтаксисБольшогоМанифестаПроекции.проверить(данные) { путь, набор in ключи[путь] = набор }
        #expect(итог.узлы == 6 && итог.объекты == 3)
        #expect(ключи["/записи/0"] == Set([Data("a/b".utf8), Data("x".utf8)]) && ключи["/записи/1"] == [])
        #expect(throws: (any Error).self) { try СинтаксисБольшогоМанифестаПроекции.проверить(Data(#"{"a":0,"\u0061":1}"#.utf8)) }
    }
    @Test("Повреждённый синтаксис, глубокий вход и превышение 32 MiB закрываются")
    func пределыИОстаток() throws {
        for строка in ["{}x", "{\"a\":}", String(repeating: "[", count: 65) + "0" + String(repeating: "]", count: 65)] {
            #expect(throws: (any Error).self) { try СинтаксисБольшогоМанифестаПроекции.проверить(Data(строка.utf8)) }
        }
        #expect(throws: (any Error).self) { try СинтаксисБольшогоМанифестаПроекции.проверить(Data(repeating: 32, count: 33_554_433)) }
    }

    @Test("Историческая пара находится только по exact file target, без допуска redirect")
    func историческийLookup() throws {
        let (данные, опора) = try фикстура(), индекс = try ИсторическийМанифестПроекции.прочитать(данные, опора: опора)
        #expect(индекс.пары.count == 1 && индекс.найти(цель)?.исходныйПуть == "README.md")
        #expect(индекс.найти("Proyekcii/Bratislavskaya-pamyatj/fajlyi") == nil && индекс.найти(путьМанифеста) == nil)
        let хэш = хэшПутей(Data("x".utf8))
        let итог = try #require(индекс.сверить(цель, хэшТекущегоИсточника: хэш, режимТекущегоИсточника: "100644", размерТекущегоИсточника: 1,
            хэшТекущейПроекции: хэш, режимТекущейПроекции: "100644", естьФрагмент: true))
        #expect(итог.исходникСовпал && итог.проекцияСовпала && !итог.перенаправлениеРазрешено && !итог.якорьПроверен)
        #expect(итог.препятствия.contains("нет-доказательства-якоря"))
    }

    @Test("Дубли, компоненты, unknown schema fields и несогласованный output set закрываются")
    func повреждённыеПары() throws {
        for вариант in 0..<9 {
            let (данные, опора) = try фикстура { корень in
                var записи = корень["записи"] as! [[String: Any]]
                switch вариант {
                case 0: записи.append(записи[0]); корень["записи"] = записи
                case 1: записи[0]["исходный_путь"] = "other.md"; корень["записи"] = записи
                case 2: корень["допуск"] = true
                case 3: корень["итоговые_файлы"] = [цель]
                case 4: записи[0]["хэш_цели"] = "sha256:" + String(repeating: "0", count: 64); корень["записи"] = записи
                case 5: корень["схема"] = (корень["схема"] as! String).decomposedStringWithCanonicalMapping
                case 6: записи[0]["класс_содержимого"] = (записи[0]["класс_содержимого"] as! String).decomposedStringWithCanonicalMapping; корень["записи"] = записи
                case 7: записи[0]["тип"] = (записи[0]["тип"] as! String).decomposedStringWithCanonicalMapping; корень["записи"] = записи
                default:
                    let значение = записи[0].removeValue(forKey: "исходный_путь")!
                    записи[0]["исходный_путь".decomposedStringWithCanonicalMapping] = значение; корень["записи"] = записи
                }
            }
            #expect(throws: (any Error).self) { try ИсторическийМанифестПроекции.прочитать(данные, опора: опора) }
        }
    }

    func заменитьПути(_ пути: [String], _ корень: inout [String: Any]) {
        let образец = (корень["записи"] as! [[String: Any]])[0]
        корень["записи"] = пути.map { путь -> [String: Any] in
            var запись = образец
            запись["исходный_путь"] = путь
            запись["целевой_путь"] = "Proyekcii/Bratislavskaya-pamyatj/fajlyi/" + путь
            запись["компоненты_пути"] = путь.split(separator: "/").map { часть -> [String: Any] in
                ["исходный": String(часть), "целевая_основа": String(часть), "сохранённое_расширение": "", "целевой": String(часть), "изменён": false]
            }
            return запись
        }
        корень["итоговые_файлы"] = (пути.map { "Proyekcii/Bratislavskaya-pamyatj/fajlyi/" + $0 } + [путьМанифеста]).sorted(by: порядокПутей)
    }

    @Test("Файловый лист не может одновременно быть предком другого файла")
    func файлИКаталог() throws {
        for пути in [["a", "a/b"], ["a/b", "a"]] {
            let (данные, опора) = try фикстура { заменитьПути(пути, &$0) }
            #expect(throws: (any Error).self) { try ИсторическийМанифестПроекции.прочитать(данные, опора: опора) }
        }
    }

    @Test("Непересекающиеся исходники не обходят file-directory guard целей")
    func толькоЦелевойКонфликт() throws {
        for обратный in [false, true] {
            let исходные = обратный ? ["b/c", "a"] : ["a", "b/c"], цели = обратный ? ["x/y", "x"] : ["x", "x/y"]
            let (данные, опора) = try фикстура { корень in
                заменитьПути(исходные, &корень)
                var записи = корень["записи"] as! [[String: Any]]
                for номер in записи.indices {
                    записи[номер]["целевой_путь"] = "Proyekcii/Bratislavskaya-pamyatj/fajlyi/" + цели[номер]
                    let старые = исходные[номер].split(separator: "/"), новые = цели[номер].split(separator: "/")
                    записи[номер]["компоненты_пути"] = zip(старые, новые).map { старый, новый -> [String: Any] in
                        ["исходный": String(старый), "целевая_основа": String(новый), "сохранённое_расширение": "", "целевой": String(новый), "изменён": Data(старый.utf8) != Data(новый.utf8)]
                    }
                }
                корень["записи"] = записи
                корень["итоговые_файлы"] = (цели.map { "Proyekcii/Bratislavskaya-pamyatj/fajlyi/" + $0 } + [путьМанифеста]).sorted(by: порядокПутей)
            }
            do {
                _ = try ИсторическийМанифестПроекции.прочитать(данные, опора: опора)
                Issue.record("Принят целевой file-directory конфликт")
            } catch ОтказКорпусаСсылок.условие(let причина) {
                #expect(причина == (обратный ? "файл-был-каталогом-исторического-пути" : "файл-стал-предком-исторического-пути"))
            }
        }
    }

    @Test("Объявленные исключения и их case-алиасы не становятся исходниками")

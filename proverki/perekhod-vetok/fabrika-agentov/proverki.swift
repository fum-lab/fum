private func адресФикстуры() -> АдресУзла {
    АдресУзла(репозиторий: "org/fork", ветка: "refs/heads/task", путьПамяти: "узел/память")
}
private func исполнительФикстуры() -> ЭкземплярУзла {
    ЭкземплярУзла(хост: "host-a", воплощение: "instance-a", задача: "task-a", родитель: "parent-a", модель: "gpt-6.1-terra", усилие: "ultra", рабочееДерево: "work/a", идентификаторПамяти: nil, кореньПамяти: nil)
}
private func назначениеФикстуры(_ каталог: URL) throws -> НазначениеПространства {
    var сведения = stat()
    guard lstat(каталог.path, &сведения) == 0 else { throw ОшибкаВладения.недоступно }
    return НазначениеПространства(адрес: адресФикстуры(), хост: "host-a", физическийКорень: каталог.path,
        устройство: UInt64(bitPattern: Int64(сведения.st_dev)), inode: UInt64(сведения.st_ino))
}
private func создатьВладение(_ каталог: URL, исполнитель: ЭкземплярУзла = исполнительФикстуры()) throws -> ЛокальноеВладение {
    try ЛокальноеВладение(адрес: адресФикстуры(), исполнитель: исполнитель, каталог: каталог.path,
        назначение: назначениеФикстуры(каталог))
}
private func подготовитьФайлВладения() throws -> (URL, ЛокальноеВладение) {
    let каталог = FileManager.default.temporaryDirectory.resolvingSymlinksInPath().appendingPathComponent(UUID().uuidString, isDirectory: true)
    try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: false)
    let файл = каталог.appendingPathComponent(try адресФикстуры().ключВладения())
    guard FileManager.default.createFile(atPath: файл.path, contents: Data(), attributes: [.posixPermissions: 0o600]) else {
        throw ОшибкаВладения.недоступно
    }
    return (каталог, try создатьВладение(каталог))
}


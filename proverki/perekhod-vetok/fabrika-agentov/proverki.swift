@Suite("Предпросмотр committed имён без эффектов")
struct ПроверкиПредпросмотраИмён {
    private func политика(владельцы: [String: String] = [:], псевдонимы: [String: String] = [:], источник: String? = nil) -> ПолитикаПредпросмотраФабрики {
        ПолитикаПредпросмотраФабрики(схема: "fum.политика-предпросмотра-фабрики.1",
            коммит: String(repeating: "a", count: 40), дерево: String(repeating: "b", count: 40),
            источникНазначений: "синтетическая фикстура", исключения: ["mirror": "внешнее зеркало"],
            роли: [:], владельцы: владельцы, псевдонимы: псевдонимы, источникПсевдонимов: источник)
    }
    private func записи(_ пути: [String]) -> Data {
        Data(пути.map { "100644 blob \(String(repeating: "c", count: 40))\t\($0)\0" }.joined().utf8)
    }
    @Test func полныйУчётИПричиныИсключений() throws {
        let вход = записи(["README.md", "узел/код/a.swift", "узел/node_modules/x", "mirror/внутри/x", "Proyekcii/x.md", "Журнал/этап/запрос.md", "Журнал/README.md"])
        let итог = try ПредпросмотрИмёнФабрики.построить(вход, политика: политика())
        #expect(итог.записей == 7)
        #expect(итог.учтено == 3)
        #expect(итог.исключено == 4)
        #expect(итог.причиныИсключений.values.reduce(0, +) == 4)
        #expect(итог.узлы.first { $0.путь == "Журнал" }?.исключение == nil)
        #expect(итог.узлы.first { $0.путь == "узел" }?.дети == ["узел/код", "узел/node_modules"].sorted())
    }
    @Test func порядокНеВлияетНаГраф() throws {
        let пути = ["а/б/1", "а/в/2", "г/3"]
        let прямой = try ПредпросмотрИмёнФабрики.построить(записи(пути), политика: политика())
        let обратный = try ПредпросмотрИмёнФабрики.построить(записи(Array(пути.reversed())), политика: политика())
        #expect(прямой.узлы == обратный.узлы)
    }
    @Test func неподтверждённыйПсевдонимНеДаётВладения() throws {
        let вход = записи(["а/x", "b/x", "а/вложенный/x", "b/вложенный/x"])
        #expect(throws: (any Error).self) {
            try ПредпросмотрИмёнФабрики.построить(вход, политика: политика(псевдонимы: ["b": "а"]))
        }
        let итог = try ПредпросмотрИмёнФабрики.построить(вход,

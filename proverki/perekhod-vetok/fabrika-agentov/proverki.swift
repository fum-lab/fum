        #expect(итог.обработаноПотребителем)
        #expect(!итог.политикаПрименена)
    }
    @Test func недопустимыеМетаданныеИПределОтклоняются() throws {
        let (индекс, политика) = try входы()
        var объект = try #require(JSONSerialization.jsonObject(with: индекс) as? [String: Any])

        #expect(итог.обработаноПотребителем)
        #expect(!итог.политикаПрименена)
        #expect(итог.коммитИндекса == "2e1904f6094828c73fcf23a185d710a0dc8336ad")
        #expect(итог.коммитПолитики == "df60f239c178a6b3bd9274ce190385089579b706")

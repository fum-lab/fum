private actor ФикстураХранилища: ХранилищеПопыток {
    private var намерения: [String: НамерениеПопытки] = [:]
    private var исходы: [String: ИсходПопытки] = [:]
    private var сверки: [String: СвидетельствоСверки] = [:]
    private let долговечность: Bool

    init(долговечность: Bool = true) { self.долговечность = долговечность }
    func поддерживаетДолговечнуюЗапись() async -> Bool { долговечность }
    func установитьНамерение(_ намерение: НамерениеПопытки) async throws -> ИтогУстановкиНамерения {
        if let прежнее = намерения[намерение.идентификатор] {
            return прежнее == намерение ? .существует : .конфликт
        }
        намерения[намерение.идентификатор] = намерение
        return .создано
    }
    func установитьИсход(_ исход: ИсходПопытки, для намерения: НамерениеПопытки) async throws -> ИтогУстановкиИсхода {
        guard self.намерения[намерения.идентификатор] == намерения else { return .конфликт }
        if сверки[намерения.идентификатор] != nil && исход != .неизвестен { return .конфликт }
        if let прежний = исходы[намерения.идентификатор] {
            return прежний == исход ? .существует : .конфликт
        }
        исходы[намерения.идентификатор] = исход
        return .создано
    }
    func намерение(идентификатор: String) async throws -> НамерениеПопытки? { намерения[идентификатор] }
    func исход(идентификатор: String) async throws -> ИсходПопытки? { исходы[идентификатор] }
    func установитьСверку(_ сверка: СвидетельствоСверки, для намерения: НамерениеПопытки) async throws -> ИтогУстановкиИсхода {
        guard self.намерения[намерения.идентификатор] == намерения else { return .конфликт }
        if let исход = исходы[намерения.идентификатор], исход != .неизвестен { return .конфликт }
        if let прежняя = сверки[намерения.идентификатор] { return прежняя == сверка ? .существует : .конфликт }
        сверки[намерения.идентификатор] = сверка
        return .создано
    }
    func сверка(идентификатор: String) async throws -> СвидетельствоСверки? { сверки[идентификатор] }
}

private struct ФикстураGit: ЧитательGit {
    let код: Int32?
    func выполнитьЧтение(_ запрос: ЗапросНаблюденияGit) async -> Int32? {
        guard запрос.программа == "/usr/bin/git",
              запрос.аргументы.count == 4,
              Array(запрос.аргументы.prefix(2)) == ["merge-base", "--is-ancestor"],
              запрос.предельноеВремяСекунды == 30 else { return nil }
        return код
    }
}

private func командаФикстурыGit(_ аргументы: [String], каталог: URL) throws -> String {
    let процесс = Process()
    процесс.executableURL = URL(fileURLWithPath: "/usr/bin/git")
    процесс.currentDirectoryURL = каталог
    процесс.arguments = ["-c", "core.hooksPath=/dev/null", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid"] + аргументы
    процесс.environment = ["PATH": "/usr/bin:/bin", "LC_ALL": "C", "GIT_CONFIG_NOSYSTEM": "1", "GIT_TERMINAL_PROMPT": "0"]
    let вывод = Pipe()
    процесс.standardOutput = вывод
    процесс.standardError = FileHandle.nullDevice
    try процесс.run()
    процесс.waitUntilExit()
    guard процесс.terminationReason == .exit, процесс.terminationStatus == 0 else { throw ОшибкаФикстурыGit.сбой }
    return String(decoding: вывод.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)
}


private struct Фикстура {
    let корень: URL
    let исходник = Data("legacy\n".utf8)

    init() throws {
        корень = FileManager.default.temporaryDirectory
            .appendingPathComponent("fum-route-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(
            at: корень.appendingPathComponent("Правила/агентов", isDirectory: true),
            withIntermediateDirectories: true)
        try FileManager.default.createDirectory(
            at: корень.appendingPathComponent(
                "Инструменты/fum-dekompoziciya-pravil-agentov", isDirectory: true),
            withIntermediateDirectories: true)
        try Data("Тема\n".utf8).write(
            to: корень.appendingPathComponent("Правила/агентов/tema.md"))
        try Data("Навык\n".utf8).write(
            to: корень.appendingPathComponent(
                "Инструменты/fum-dekompoziciya-pravil-agentov/SKILL.md"))
        try записатьКорень()
        try записатьИнвентарь(инвентарь())
    }

    func удалить() {
        try? FileManager.default.removeItem(at: корень)
    }

    func путь(_ относительный: String) -> URL {
        корень.appendingPathComponent(относительный)
    }

    func записатьКорень(
        правило: String = "<!-- FUM-ПРАВИЛО: RULE-ROOT -->",
        маршрутЧтения: String = "<!-- FUM-МАРШРУТ: read =>Правила/агентов/tema.md -->",
        маршрутДополнения: String = "<!-- FUM-МАРШРУТ: extra =>Инструменты/fum-dekompoziciya-pravil-agentov/SKILL.md -->"
    ) throws {
        let текст = [
            "# Правила",
            правило,
            маршрутЧтения,
            маршрутДополнения,
            "<!-- FUM-МАРШРУТ: правила =>Правила/агентов/tema.md;Правила/агентов/инвентарь-правил.json;Инструменты/fum-dekompoziciya-pravil-agentov/SKILL.md -->",
            "",
        ].joined(separator: "\n")
        try Data(текст.utf8).write(to: путь("AGENTS.md"))
    }

    func инвентарь() -> [String: Any] {
        let тема = Data("Тема\n".utf8)
        return [
            "схема": "fum.декомпозиция-правил-агентов.1",
            "исходный_снимок": [
                "commit": String(repeating: "1", count: 40),
                "blob": String(repeating: "2", count: 40),
                "sha256": хэшSHA256(исходник),
                "строк": 1,
                "unicode_символов": 7,
                "байтов": 7,
            ],
            "темы": [[
                "идентификатор": "tema",
                "путь": "Правила/агентов/tema.md",
                "полномочия": true,
                "sha256_содержания": хэшSHA256(тема),
            ]],
            "служебные_пути_изменения_правил": [
                "Правила/агентов/инвентарь-правил.json",
                "Инструменты/fum-dekompoziciya-pravil-agentov/SKILL.md",
            ],
            "маршруты": [
                ["идентификатор": "read", "пути": ["Правила/агентов/tema.md"]],
                ["идентификатор": "extra", "пути": [
                    "Инструменты/fum-dekompoziciya-pravil-agentov/SKILL.md",
                ]],
                ["идентификатор": "правила", "пути": [
                    "Правила/агентов/tema.md",
                    "Правила/агентов/инвентарь-правил.json",
                    "Инструменты/fum-dekompoziciya-pravil-agentov/SKILL.md",
                ]],
            ],
            "фикстуры_маршрутизации": [[
                "идентификатор": "union",
                "триггеры": ["read", "extra"],
                "ожидаемые_пути": [
                    "Инструменты/fum-dekompoziciya-pravil-agentov/SKILL.md",
                    "Правила/агентов/tema.md",
                ],
            ]],
            "исходные_единицы": [[
                "идентификатор": "SOURCE-1",
                "номер_строки": 1,
                "начало_байта": 0,
                "конец_байта": 7,
                "sha256": хэшSHA256(исходник),
                "класс": "правило",
                "требует_правило": true,
            ]],
            "правила": [[
                "идентификатор": "RULE-ROOT",
                "статус": "действует",
                "приоритет": "P0-ядро",
                "области": ["всегда"],
                "триггеры": ["правила"],
                "семантический_ключ": "root",
                "назначение": ["путь": "AGENTS.md", "якорь": "RULE-ROOT"],
                "источники": ["SOURCE-1"],
            ]],
        ]
    }

    func записатьИнвентарь(_ значение: [String: Any]) throws {
        let данные = try JSONSerialization.data(
            withJSONObject: значение, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes])
        try данные.write(to: путь("Правила/агентов/инвентарь-правил.json"))
    }

    func выполнить(_ триггеры: [String] = ["read", "extra"]) throws -> РезультатМаршрутаПравил {
        try ВалидаторМаршрутаПравил.проверить(
            корень: корень, триггеры: триггеры, источник: .данные(исходник))
    }
}

private func сФикстурой(_ тело: (Фикстура) throws -> Void) throws {
    let фикстура = try Фикстура()
    defer { фикстура.удалить() }
    try тело(фикстура)
}

private func ожидатьОтказ(
    _ категория: ОтказМаршрутаПравил.Категория,
    _ действие: () throws -> Void,
    sourceLocation: SourceLocation = #_sourceLocation
) {
    do {
        try действие()
        Issue.record("Ожидался отказ \(категория)", sourceLocation: sourceLocation)
    } catch let отказ as ОтказМаршрутаПравил {
        #expect(отказ.категория == категория, sourceLocation: sourceLocation)
    } catch {
        Issue.record("Неожиданный тип ошибки: \(error)", sourceLocation: sourceLocation)
    }
}


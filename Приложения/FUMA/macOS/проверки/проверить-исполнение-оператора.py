#!/usr/bin/env python3
"""Настоящий бинарник FUMA: накопление, повтор, отказы и профиль открытого входа."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time


def проверить(бинарник: Path, корень: Path) -> dict:
    определение = корень / "Приложения/FUMA/Sources/FUMStructuringOperatorMemory/Определения/нормализация.json"
    фикстура = корень / "Приложения/FUMA/macOS/проверки/фикстуры/вход-оператора.txt"
    измерения = []
    путиИсходников = [Path(__file__).resolve(),
        корень / "Приложения/FUMA/macOS/Package.swift",
        корень / "Приложения/FUMA/macOS/FUM.xcodeproj/project.pbxproj",
        корень / "Приложения/FUMA/macOS/Sources/FUMApp/FUMApp.swift"]
    for каталогИсходников in ["Приложения/FUMA/macOS/Sources/ИсполнениеОператора",
            "Приложения/FUMA/macOS/Sources/ПутиИсполнения",
            "Приложения/FUMA/Sources/FUMStructuringOperatorMemory",
            "Приложения/FUMA/Sources/КонтейнерНаблюдений"]:
        путиИсходников.extend(sorted((корень / каталогИсходников).rglob("*.swift")))
    исходники = {str(путь.relative_to(корень)): hashlib.sha256(путь.read_bytes()).hexdigest() for путь in путиИсходников}
    исходные = {str(путь.relative_to(корень)): hashlib.sha256(путь.read_bytes()).hexdigest()
        for путь in [определение, фикстура]}
    with tempfile.TemporaryDirectory(prefix="fuma-оператор-") as временный:
        каталог = Path(временный).resolve()
        журнал = каталог / "наблюдения"
        журнал.mkdir(mode=0o700)
        среда = dict(os.environ)
        # Любая преждевременная инициализация обычных путей приложения завершится отказом.
        среда.update(FUM_RUNTIME_ROOT="недопустимый-относительный-путь",
            FUM_MEMORY_ROOT="недопустимый-относительный-путь", FUM_DOCUMENTS_ROOT="недопустимый-относительный-путь")
        вход = каталог / "вход.txt"
        вход.write_bytes(фикстура.read_bytes())
        файл = каталог / "определение.json"
        файл.write_bytes(определение.read_bytes())
        аргументы = ["--выполнить-оператор", "--определение", str(файл), "--вход", str(вход),
            "--тип-входа", "текст", "--журнал", str(журнал)]

        def запуск(параметры: list[str], успех: bool = True) -> dict | None:
            начало = time.perf_counter_ns()
            процесс = subprocess.run([str(бинарник), *параметры], env=среда, capture_output=True, timeout=15)
            длительность = time.perf_counter_ns() - начало
            assert процесс.returncode == (0 if успех else 2), (процесс.returncode, процесс.stderr.decode())
            if not успех:
                assert процесс.stdout == b"", "Отказ не должен содержать успешного результата"
                return None
            if "--профиль" in параметры:
                метки = [json.loads(строка) for строка in процесс.stderr.splitlines()]
                assert {"вход", "декодирование", "исполнение", "сохранение"} <= {метка["стадия"] for метка in метки}
                assert all(метка["наносекунды"] >= 0 and метка["исход"] == "успешно" for метка in метки)
                измерения.append({"процесс_наносекунды": длительность, "метки": метки})
            else:
                assert процесс.stderr == b"", процесс.stderr.decode()
            return json.loads(процесс.stdout)

        первый = запуск(аргументы)
        assert первый["наблюдение"]["результат"] == {"тип": "текст", "значение": "привет ёж"}
        идентификатор = первый["квитанция"]["описание"]["идентификатор"]
        сегмент = журнал / "сегмент.fumobs"
        началоИстории = сегмент.read_bytes()
        вход.unlink()
        файл.unlink()
        повтор = запуск(["--повторить-оператор", идентификатор, "--журнал", str(журнал)])
        assert повтор["наблюдение"] == первый["наблюдение"]
        assert повтор["квитанция"]["хэш"] == первый["квитанция"]["хэш"]
        assert повтор["квитанция"]["описание"]["идентификатор"] != идентификатор
        assert сегмент.read_bytes().startswith(началоИстории) and сегмент.stat().st_size > len(началоИстории)
        вход.write_bytes(фикстура.read_bytes())
        файл.write_bytes(определение.read_bytes())
        for _ in range(5):
            образец = запуск([*аргументы, "--профиль"])
            assert образец["наблюдение"] == первый["наблюдение"]
        байтовоеОпределение = определение.with_name("UTF-8-в-UTF-32LE.json")
        исходные[str(байтовоеОпределение.relative_to(корень))] = hashlib.sha256(байтовоеОпределение.read_bytes()).hexdigest()
        файл.write_bytes(байтовоеОпределение.read_bytes())
        вход.write_bytes("Aё🙂".encode())
        байтовыеАргументы = ["байты" if часть == "текст" else часть for часть in аргументы]
        байтовый = запуск(байтовыеАргументы)
        assert байтовый["наблюдение"]["результат"] == {"тип": "байты", "значение": list("Aё🙂".encode("utf-32le"))}
        assert len(байтовый["наблюдение"]["трасса"]) == 3
        байтоваяКвитанция = байтовый["квитанция"]
        байтовыйИдентификатор = байтоваяКвитанция["описание"]["идентификатор"]
        историяДоБайтовогоПовтора = сегмент.read_bytes()
        вход.unlink()
        файл.unlink()
        байтовыйПовтор = запуск(["--повторить-оператор", байтовыйИдентификатор, "--журнал", str(журнал)])
        assert байтовыйПовтор["наблюдение"]["результат"] == {
            "тип": "байты", "значение": [0x41, 0, 0, 0, 0x51, 0x04, 0, 0, 0x42, 0xF6, 0x01, 0]}
        assert байтовыйПовтор["наблюдение"] == байтовый["наблюдение"]
        assert len(байтовыйПовтор["наблюдение"]["трасса"]) == 3
        assert байтовыйПовтор["квитанция"]["хэш"] == байтоваяКвитанция["хэш"]
        assert байтовыйПовтор["квитанция"]["размер"] == байтоваяКвитанция["размер"]
        assert байтовыйПовтор["квитанция"]["описание"]["идентификатор"] != байтовыйИдентификатор
        assert сегмент.read_bytes().startswith(историяДоБайтовогоПовтора)
        assert сегмент.stat().st_size > len(историяДоБайтовогоПовтора)
        файл.write_bytes(байтовоеОпределение.read_bytes())
        вход.write_bytes(b"\xff")
        запуск(байтовыеАргументы, успех=False)
        вход.write_bytes(фикстура.read_bytes())
        файл.write_bytes(определение.read_bytes())
        прежде = сегмент.read_bytes()
        запуск([*аргументы, "--request-permissions"], успех=False)
        запуск([*аргументы, "--permission-status"], успех=False)
        запуск([*аргументы, "--вход", str(вход)], успех=False)
        запуск(["--повторить-оператор", "нет-такой-записи", "--журнал", str(журнал)], успех=False)
        описание = json.loads(определение.read_bytes())
        описание["шаги"][0]["оператор"] = "несуществующий"
        файл.write_text(json.dumps(описание, ensure_ascii=False))
        запуск(аргументы, успех=False)
        файл.write_bytes(b'{"broken":')
        запуск(аргументы, успех=False)
        файл.write_bytes(определение.read_bytes())
        вход.write_bytes(b'\xff')
        запуск(аргументы, успех=False)
        вход.write_bytes(фикстура.read_bytes())
        запуск([*аргументы[:-1], str(корень)], успех=False)
        ссылка = каталог / "ссылка-на-журнал"
        ссылка.symlink_to(журнал, target_is_directory=True)
        запуск([*аргументы[:-1], str(ссылка)], успех=False)
        журнал.chmod(0o755)
        запуск(аргументы, успех=False)
        журнал.chmod(0o700)
        assert сегмент.read_bytes() == прежде
        # Неполный хвост не удаляется автоматически ради следующего успеха.
        with сегмент.open("ab") as поток:
            поток.write("незавершённая-запись".encode())
        повреждённый = сегмент.read_bytes()
        запуск(аргументы, успех=False)
        assert сегмент.read_bytes() == повреждённый
    assert all(hashlib.sha256((корень / путь).read_bytes()).hexdigest() == хэш for путь, хэш in исходники.items())
    return {"схема": "fuma.проверка-командного-исполнения.1", "результат": "успешно", "исходники_sha256": исходники,
        "бинарник_sha256": hashlib.sha256(бинарник.read_bytes()).hexdigest(),
        "входы_sha256": исходные, "профиль": измерения,
        "граница": "Последовательные процессы одного бинарника; сборка исключена; вложенные метки не суммируются."}


def главная() -> None:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--бинарник", type=Path, required=True)
    разбор.add_argument("--корень", type=Path, default=Path(__file__).resolve().parents[4])
    разбор.add_argument("--профиль-выход", type=Path)
    параметры = разбор.parse_args()
    результат = проверить(параметры.бинарник.resolve(strict=True), параметры.корень.resolve(strict=True))
    данные = json.dumps(результат, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    if параметры.профиль_выход:
        параметры.профиль_выход.write_text(данные)
    print(данные, end="")


if __name__ == "__main__":
    главная()

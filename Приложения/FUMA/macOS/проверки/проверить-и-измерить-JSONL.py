def собрать_публичную_сводку(профили_байты, записи_байты, ожидания):
    """Чистое преобразование двух исходных профилей и двух оригинальных v4-записей."""
    проверить_ожидания_сводки(ожидания)
    потребовать_сводку(type(профили_байты) is list and len(профили_байты) == 2
                      and type(записи_байты) is list and len(записи_байты) == 2,
                      'Ожидаются два исходных профиля и две исходные записи')
    результаты = []
    исходные_профили = []
    исходные_записи = []
    for индекс in range(2):
        потребовать_сводку(type(профили_байты[индекс]) is bytes and type(записи_байты[индекс]) is bytes,
                          'Исходное свидетельство должно быть bytes')
        потребовать_сводку(хэш(профили_байты[индекс]) == ожидания['хэши_профилей'][индекс]
                          and хэш(записи_байты[индекс]) == ожидания['хэши_записей'][индекс],
                          'Не совпал независимый хэш оригинальных байтов')
        профиль = строгий_объект_сводки(профили_байты[индекс])
        запись = строгий_объект_сводки(записи_байты[индекс])
        проверить_запись_сводки(запись, записи_байты[индекс], ожидания, индекс)
        результаты.append(проверить_и_свести_профиль(профиль, профили_байты[индекс],
                                                   записи_байты[индекс], ожидания, индекс))
        исходные_профили.append(профиль)
        исходные_записи.append(запись)
    потребовать_сводку(исходные_записи[0]['порядок'] != исходные_записи[1]['порядок'],
                      'Исходные записи повторяют порядок одной сессии')
    потребовать_сводку(исходные_профили[0]['архитектура'] == исходные_профили[1]['архитектура'],
                      'Профили имеют разные наблюдённые архитектуры хоста')
    return {'схема': 'fuma.свидетельства-конечного-JSONL-среза.2',
            'сессия': ожидания['сессия'], 'процессов': 204, 'профили': результаты,
            'оптимизированная_сборка': None, 'сравнение_с_языковой_моделью': None,
            'граница': ГРАНИЦА_ПУБЛИЧНОГО_ПРОФИЛЯ}


def физический_путь_сводки(значение, частный=False):
    потребовать_сводку(type(значение) is str, 'Ожидается явный путь')
    путь = Path(значение)
    потребовать_сводку(путь.is_absolute() and путь.resolve(strict=True) == путь
                      and путь.is_file()
                      and not any(часть.is_symlink() for часть in [путь, *путь.parents]),
                      'Требуется физический абсолютный путь обычного файла')
    if частный:
        потребовать_сводку(not any((часть / '.git').exists() for часть in путь.parents),
                          'Приватный вход должен быть вне Git')
    return путь



def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def объект(данные):
    return json.loads(данные)


def сверить(ответ, эталон):
    запись = ответ['запись']
    assert ответ['схема'] == 'fuma.результат-JSONL.1'
    assert запись['схема'] == 'fuma.исполнение-JSONL.1'
    assert запись.get('отказ') is None
    assert запись['сыройВход']['хэш'] == эталон['sha256']
    assert запись['сыройВход']['размер'] == эталон['байты']
    assert len(запись['рамки']) == len(эталон['рамки'])
    for рамка, ожидаемая in zip(запись['рамки'], эталон['рамки']):
        assert рамка['позиция'] == {ключ: ожидаемая[ключ] for ключ in ['номер', 'начало', 'конец', 'sha256']}
        данные = base64.b64decode(рамка['наблюдение'], validate=True)
        assert хэш(данные) == рамка['sha256Наблюдения']
        наблюдение = объект(данные)
        assert наблюдение['схема'] == 'fum.наблюдение-оператора.2'
        assert объект(наблюдение['результат']['значение']) == ожидаемая['ожидание']
    assert запись['сыройХвост'] == эталон['хвост']
    assert запись['неИсполненныйСуффикс'] == эталон['хвост']
    assert запись['границаLF']['байты'] == эталон['хвост']['начало']
    assert запись['исполненныйПрефикс'] == запись['границаLF']


def исполнить(бинарник, аргументы, папка, имя):
    начало = time.perf_counter_ns()
    процесс = subprocess.Popen([str(бинарник), *аргументы], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    try:
        вывод, ошибки = процесс.communicate(timeout=60)
    except subprocess.TimeoutExpired:
        процесс.kill()
        вывод, ошибки = процесс.communicate()
        (папка / (имя + '.stdout')).write_bytes(вывод)
        (папка / (имя + '.stderr')).write_bytes(ошибки)
        raise RuntimeError('fum: тайм-аут60с, процесс завершён')
    длительность = time.perf_counter_ns() - начало
    (папка / (имя + '.stdout')).write_bytes(вывод)
    (папка / (имя + '.stderr')).write_bytes(ошибки)
    if процесс.returncode:
        raise RuntimeError(f'fum: код{процесс.returncode}; stderr sha256={хэш(ошибки)}')
    assert len(вывод) <= 1_048_576
    метки = []
    for строка in ошибки.splitlines():
        try:
            метка = объект(строка)
        except (ValueError, UnicodeError):
            continue
        if isinstance(метка, dict) and set(метка) == {'стадия', 'наносекунды', 'исход', 'глубина'}:
            метки.append(метка)
    return объект(вывод), {'PID': процесс.pid, 'код': процесс.returncode,
        'длительность_нс': длительность, 'stdout_байты': len(вывод),
        'stdout_sha256': хэш(вывод), 'stderr_sha256': хэш(ошибки), 'метки': метки}


def выполнить():
    проверить_режим_интерпретатора(sys.flags.optimize)
    идентификатор_проверки = канонический_идентификатор_проверки(os.environ.get('FUM_CHECK_RUN_ID'))
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--бинарник', required=True, type=Path)
    разбор.add_argument('--выход', required=True, type=Path)
    разбор.add_argument('--повторов', type=int, default=25)
    разбор.add_argument('--конфигурация', choices=['Debug', 'Release', 'неизвестно'], default='неизвестно')
    вход = разбор.parse_args()
    assert 25 <= вход.повторов <= 100
    бинарник = вход.бинарник.resolve(strict=True)
    выход = вход.выход
    потребовать_сводку(выход.is_absolute(), 'Требуется абсолютный приватный выход')
    потребовать_сводку(not any(путь.is_symlink() for путь in [выход, *выход.parents]),
                      'Символическая ссылка в пути выхода')
    потребовать_сводку(выход.parent.is_dir() and выход.parent.resolve(strict=True) == выход.parent,
                      'Родитель выхода должен существовать и быть физическим')
    assert not выход.exists()
    for предок in [выход.parent, *выход.parent.parents]:
        assert not (предок / '.git').exists(), 'Результат должен быть вне Git'
    assert выход.parent.is_dir()
    снимок_бинарника = хэш(бинарник.read_bytes())
    пакет = Path(__file__).resolve().parents[1]
    программа = пакет / 'Операторы/сообщения-журнала-Codex.json'
    сырой = пакет / 'проверки/фикстуры/срез-журнала-Codex.jsonl'
    оракул = пакет / 'проверки/фикстуры/срез-журнала-Codex-эталон.json'
    исходники = [Path(__file__).resolve(), программа, сырой, оракул]
    снимок = {str(путь.relative_to(пакет)): хэш(путь.read_bytes()) for путь in исходники}
    эталон = объект(оракул.read_bytes())
    assert хэш(сырой.read_bytes()) == эталон['sha256']
    началоСтроки = b'{"type":"event_msg","padding":"'
    конецСтроки = b'"}\n'
    большаяСтрока = началоСтроки + b'A' * (262144 - len(началоСтроки) - len(конецСтроки)) + конецСтроки
    большой = большаяСтрока * 4
    пустойХвост = {'начало': len(большой), 'конец': len(большой), 'sha256': хэш(b'')}
    эталонБольшого = {'sha256': хэш(большой), 'байты': len(большой), 'хвост': пустойХвост,
        'пик_строки': len(большаяСтрока), 'рамки': [
            {'номер': номер + 1, 'начало': номер * 262144, 'конец': (номер + 1) * 262144,
                'sha256': хэш(большаяСтрока), 'ожидание': []} for номер in range(4)]}
    корпусы = [('нативный', сырой.read_bytes(), эталон), ('предел-1МиБ', большой, эталонБольшого)]
    повторы = []
    архив = выход.with_name(выход.stem + '-каналы')
    архив.mkdir(mode=0o700)
    with tempfile.TemporaryDirectory(prefix='fum-JSONL-', dir=выход.parent) as временный:
        рабочий = Path(временный).resolve()
        for имяКорпуса, байтыКорпуса, эталонКорпуса in корпусы:
            for номер in range(вход.повторов):
                папка = рабочий / (имяКорпуса + '-' + str(номер))
                папка.mkdir(mode=0o700)
                журнал = папка / 'память'
                журнал.mkdir(mode=0o700)
                определения = папка / 'определения'
                определения.mkdir(mode=0o700)
                файлПрограммы = определения / 'замыкание.json'
                файлПрограммы.write_bytes(программа.read_bytes())
                for индекс, определение in enumerate(объект(файлПрограммы.read_bytes())['определения']):
                    (определения / f'{индекс}.json').write_text(json.dumps(определение, ensure_ascii=False))
                источник = папка / 'вход.jsonl'
                источник.write_bytes(байтыКорпуса)
                первый, прямой = исполнить(бинарник, ['--исполнить-JSONL', '--определение', str(файлПрограммы),
                    '--вход', str(источник), '--журнал', str(журнал), '--профиль'], архив, f'{имяКорпуса}-{номер}-прямой')
                сверить(первый, эталонКорпуса)
                источник.unlink()
                for файл in определения.iterdir():
                    файл.unlink()
                определения.rmdir()
                assert not источник.exists() and not определения.exists()
                второй, повтор = исполнить(бинарник, ['--повторить-JSONL', первый['квитанция']['описание']['идентификатор'],
                    '--журнал', str(журнал), '--профиль'], архив, f'{имяКорпуса}-{номер}-повтор')
                assert прямой['PID'] != повтор['PID']
                assert первый['запись'] == второй['запись']
                assert первый['квитанция']['описание']['идентификатор'] != второй['квитанция']['описание']['идентификатор']
                assert первый['квитанция']['хэш'] == второй['квитанция']['хэш']
                повторы.append({'корпус': имяКорпуса, 'номер': номер + 1, 'прямой': прямой, 'повтор': повтор,
                    'операции': первый['запись']['учтеноОпераций'], 'трасса': первый['запись']['записейТрассы'],
                    'сохранённые_байты': первый['квитанция']['размер']})
        # Отдельный конечный срез превышает старый raw cap262144; tail недекодируем.
        папка = рабочий / 'расширенный'
        папка.mkdir(mode=0o700)
        журнал = папка / 'память'
        журнал.mkdir(mode=0o700)
        источник = папка / 'вход.jsonl'
        расширенный = (b'"' + b'A' * 131071 + b'"\n') * 2 + b'\xf0\x9f'
        assert len(расширенный) > 262144
        источник.write_bytes(расширенный)
        определение = папка / 'определение.json'
        определение.write_text(json.dumps({'схема': 'fum.определение-оператора.2', 'идентификатор': 'расширенный-срез',
            'версия': 1, 'правила': [], 'определения': [], 'шаги': [
                {'идентификатор': 'нижний-регистр', 'оператор': 'нижний-регистр', 'аргументы': {}}]}, ensure_ascii=False))
        первый, прямой = исполнить(бинарник, ['--исполнить-JSONL', '--определение', str(определение),
            '--вход', str(источник), '--журнал', str(журнал), '--профиль'], архив, 'расширенный-прямой')
        источник.unlink()
        определение.unlink()
        второй, повтор = исполнить(бинарник, ['--повторить-JSONL', первый['квитанция']['описание']['идентификатор'],
            '--журнал', str(журнал), '--профиль'], архив, 'расширенный-повтор')
        assert прямой['PID'] != повтор['PID'] and первый['запись'] == второй['запись']
        assert len(первый['запись']['рамки']) == 2 and первый['запись'].get('отказ') is None
        assert первый['запись']['сыройВход']['хэш'] == хэш(расширенный)
        assert первый['запись']['учтеноОпераций'] == 2 and первый['запись']['записейТрассы'] == 2
        for рамка in первый['запись']['рамки']:
            значение = объект(base64.b64decode(рамка['наблюдение']))['результат']['значение']
            assert значение == '"' + 'a' * 131071 + '"\n'
    assert снимок == {str(путь.relative_to(пакет)): хэш(путь.read_bytes()) for путь in исходники}
    конечный_хэш_бинарника = хэш(бинарник.read_bytes())
    потребовать_сводку(конечный_хэш_бинарника == снимок_бинарника,
                      'Бинарник изменился во время измерений')
    распределения = {}
    for имяКорпуса, байтыКорпуса, эталонКорпуса in корпусы:
        распределения[имяКорпуса] = {'байты': len(байтыКорпуса), 'sha256': хэш(байтыКорпуса),
            'рамок': len(эталонКорпуса['рамки']), 'пик_строки': эталонКорпуса['пик_строки']}
        for режим in ['прямой', 'повтор']:
            значения = [ряд[режим]['длительность_нс'] for ряд in повторы if ряд['корпус'] == имяКорпуса]
            распределения[имяКорпуса][режим] = {'все_нс': значения, 'минимум_нс': min(значения),
                'медиана_нс': statistics.median(значения), 'максимум_нс': max(значения)}
    результат = {'схема': 'fuma.свидетельства-JSONL.2', 'платформа': platform.system(),
        'идентификатор_запуска': идентификатор_проверки,
        'архитектура': platform.machine(), 'конфигурация': вход.конфигурация,
        'бинарник_sha256': снимок_бинарника, 'хэш_бинарника_после': конечный_хэш_бинарника,
        'исходники': снимок, 'повторов': вход.повторов,
        'срез': {'байты': эталон['байты'], 'рамок': len(эталон['рамки']), 'пик_строки': эталон['пик_строки']},
        'распределения': распределения, 'запуски': повторы,
        'расширенный': {'байты': len(расширенный), 'sha256': хэш(расширенный), 'прямой': прямой, 'повтор': повтор},
        'граница': 'macOS, процессы завершены; профили вложены и не суммируются. Запуск/чтение/fsync входят в wholeprocess; подготовка и сравнение исключены. Пик строки — длина, не RSS. Синтетический native rollout не является CLI stdout. Общая ROOT приёмка отдельно.'}
    дескриптор = os.open(выход, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(дескриптор, 'w') as файл:
        json.dump(результат, файл, ensure_ascii=False, sort_keys=True, indent=2)
        файл.write('\n')
    print(json.dumps({'схема': результат['схема'], 'повторов': вход.повторов,
        'результат_sha256': хэш(выход.read_bytes()), 'распределения': распределения}, ensure_ascii=False))




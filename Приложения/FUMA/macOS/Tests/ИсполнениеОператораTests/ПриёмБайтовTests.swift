import XCTest
import Foundation
import Darwin
import FUMStructuringOperatorMemory
import КонтейнерНаблюдений
@testable import ИсполнениеОператора

extension ПроверкиИсполнения {
    func testОтказВторогоИсходникаСохраняетПервыйБезИсполнения() throws {
        try сКаталогом { каталог, аргументы in
            let байты = try Data(contentsOf: каталог.appendingPathComponent("вход.txt"))
            let маркер = Data("\"тип\":\"сырые-байты/определение-оператора\"".utf8)
            let операции = ФайловыеОперации(запись: { дескриптор, буфер in
                if Data(буфер).range(of: маркер) != nil { throw ОшибкаКонтейнера.система(ENOSPC) }
                return try ФайловыеОперации.системные.запись(дескриптор, буфер)
            }, синхронизация: ФайловыеОперации.системные.синхронизация)
            XCTAssertThrowsError(try КомандноеИсполнениеОператора.выполнить(аргументы: аргументы, операции: операции)) {
                XCTAssertEqual($0 as? ОшибкаКонтейнера, .система(ENOSPC))
            }
            let сегмент = try Сегмент(кореньДанных: каталог, запись: false, создать: false)
            defer { сегмент.закрыть() }
            XCTAssertTrue(сегмент.естьХвост)
            XCTAssertEqual(сегмент.записи.count, 1)
            let запись = try XCTUnwrap(сегмент.записи.first)
            XCTAssertEqual(запись.описание.тип, "сырые-байты/вход-оператора")
            XCTAssertEqual(try сегмент.извлечь(запись.описание.идентификатор), байты)
        }
    }

    func testНеполныйUTF8СохраняетсяДоДекодирования() throws {
        try сКаталогом { каталог, аргументы in
            let байты = Data([0x00, 0xD1, 0x91, 0xF0, 0x9F])
            try байты.write(to: каталог.appendingPathComponent("вход.txt"))
            XCTAssertThrowsError(try КомандноеИсполнениеОператора.выполнить(аргументы: аргументы)) {
                XCTAssertEqual($0 as? ОшибкаКомандногоИсполнения, .кодировка)
            }
            let сегмент = try Сегмент(кореньДанных: каталог, запись: false, создать: false)
            defer { сегмент.закрыть() }
            let запись = try XCTUnwrap(сегмент.записи.first)
            XCTAssertEqual(запись.описание.тип, "сырые-байты/вход-оператора")
            XCTAssertEqual(try сегмент.извлечь(запись.описание.идентификатор), байты)
            XCTAssertFalse(сегмент.записи.contains { $0.описание.тип == "исполнение-оператора" })
        }
    }

    func testБайтовыйОператорСохраняетВсеЗначенияПовторыИПроисхождение() throws {
        try сКаталогом { каталог, исходные in
            let байты = Data((0...255).map(UInt8.init))
            try байты.write(to: каталог.appendingPathComponent("вход.txt"))
            let определение = ОпределениеОператора(идентификатор: "тождество-байтов", версия: 1, шаги: [])
            try определение.данные().write(to: каталог.appendingPathComponent("определение.json"))
            let аргументы = исходные.map { $0 == "текст" ? "байты" : $0 } + ["--источник-входа", "LLM"]
            for _ in 0..<2 { _ = try КомандноеИсполнениеОператора.выполнить(аргументы: аргументы) }
            let сегмент = try Сегмент(кореньДанных: каталог, запись: false, создать: false)
            defer { сегмент.закрыть() }
            let входы = сегмент.записи.filter { $0.описание.тип == "сырые-байты/вход-оператора" }
            XCTAssertEqual(входы.count, 2)
            XCTAssertEqual(Set(входы.map(\.описание.идентификатор)).count, 2)
            for запись in входы {
                XCTAssertEqual(try сегмент.извлечь(запись.описание.идентификатор), байты)
                let метаданные = try объект(запись.описание.спецификация)
                XCTAssertEqual(метаданные["заявленныйИсточник"] as? String, "LLM")
            }
            let исполнения = сегмент.записи.filter { $0.описание.тип == "исполнение-оператора" }
            XCTAssertEqual(исполнения.count, 2)
            for запись in исполнения {
                let данные = try объект(сегмент.извлечь(запись.описание.идентификатор))
                let наблюдение = try XCTUnwrap(данные["наблюдение"] as? [String: Any])
                let результат = try XCTUnwrap(наблюдение["результат"] as? [String: Any])
                XCTAssertEqual(результат["значение"] as? [UInt8], Array(байты))
            }
        }
    }

    func testОтказХраненияПредшествуетИнтерпретации() throws {
        try сКаталогом { каталог, аргументы in
            try Data([0xFF]).write(to: каталог.appendingPathComponent("определение.json"))
            var стадии: [String] = []
            let операции = ФайловыеОперации(запись: { _, _ in throw ОшибкаКонтейнера.система(ENOSPC) },
                синхронизация: ФайловыеОперации.системные.синхронизация)
            XCTAssertThrowsError(try КомандноеИсполнениеОператора.выполнить(
                аргументы: аргументы, операции: операции, профиль: { стадии.append($0.стадия) })) {
                XCTAssertEqual($0 as? ОшибкаКонтейнера, .система(ENOSPC))
            }
            XCTAssertFalse(стадии.contains("декодирование"))
            XCTAssertFalse(стадии.contains("исполнение"))
        }
    }
}

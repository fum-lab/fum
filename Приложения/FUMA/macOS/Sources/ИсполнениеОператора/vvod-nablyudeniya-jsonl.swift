private struct НастройкаВводаНаблюдения: Codable, Equatable {
    let источник: String
    let поколение: String
    let имяФайла: String
    let хэшПрограммы: String
    let приёмОпределения: String
}

private struct НамерениеРамкиНаблюдения: Codable, Equatable {
    let пакет: String
    let начало: Int
    let конец: Int
    let хэшРамки: String
    let хэшПрограммы: String
    let приём: String
    let исполнение: String
}

private struct СвязьРамкиНаблюдения: Codable, Equatable {
    let пакет: String
    let начало: Int
    let конец: Int
    let хэшРамки: String
    let хэшПрограммы: String
    let приём: String
    let исполнение: String
    let результат: Квитанция
}

private struct ПодтверждениеПакетаНаблюдения: Codable, Equatable {
    let пакет: String
    let хэшПодтверждения: String
    let хэшПрограммы: String
}

private struct ОтветВводаНаблюдения: Encodable {
    let состояние: String
    let пакет: String?
    let связи: [СвязьРамкиНаблюдения]
    let стадия: String?
    let приём: String?
    let исполнение: String?
    let хэшПакета: String?
    let подтверждение: String?
    let отклонённыеБайтыСохранены: Bool?
}

/// Конечный снимок одного файла; вызывающий обеспечивает единственного писателя истории.
public enum МостВводаНаблюденияJSONL {
    public static func выполнить(аргументы: [String], операции: ФайловыеОперации = .системные) throws -> Data {
        let допустимые: Set<String> = ["--корень-файловой-системы", "--имя-файла", "--источник",
            "--поколение", "--определение", "--журнал", "--после", "--подтверждение"]
        var значения: [String: String] = [:]
        var выбран = false
        var индекс = 0
        while индекс < аргументы.count {
            let имя = аргументы[индекс]
            if имя == "--ввод-наблюдения-JSONL" {
                guard !выбран else { throw ОшибкаКомандногоИсполнения.аргументы }
                выбран = true
                индекс += 1
            } else {
                guard допустимые.contains(имя), значения[имя] == nil, индекс + 1 < аргументы.count,
                      !аргументы[индекс + 1].isEmpty, !аргументы[индекс + 1].hasPrefix("--")
                else { throw ОшибкаКомандногоИсполнения.аргументы }
                значения[имя] = аргументы[индекс + 1]
                индекс += 2
            }
        }
        let обязательные = допустимые.subtracting(["--после", "--подтверждение"])
        guard выбран, обязательные.isSubset(of: Set(значения.keys)),
              (значения["--после"] == nil) == (значения["--подтверждение"] == nil),
              let имя = значения["--имя-файла"], !имя.contains("/"), имя != ".", имя != "..",
              let источник = значения["--источник"], let поколение = значения["--поколение"]
        else { throw ОшибкаКомандногоИсполнения.аргументы }
        let каталог = try КомандноеИсполнениеОператора.проверитьКаталог(значения["--журнал"]!)
        let корень = URL(fileURLWithPath: значения["--корень-файловой-системы"]!, isDirectory: true)
        guard let физический = realpath(корень.path, nil) else { throw ОшибкаКомандногоИсполнения.аргументы }
        defer { free(физический) }
        let физическийПуть = String(cString: физический)
        var сведенияКаталога = stat()
        guard физическийПуть == корень.path, lstat(корень.path, &сведенияКаталога) == 0,
              сведенияКаталога.st_mode & S_IFMT == S_IFDIR,
              сведенияКаталога.st_uid == geteuid(), сведенияКаталога.st_mode & 0o077 == 0,
              !каталог.pathComponents.starts(with: корень.pathComponents),
              !корень.pathComponents.starts(with: каталог.pathComponents),
              try FileManager.default.contentsOfDirectory(atPath: корень.path) == [имя]
        else { throw ОшибкаКомандногоИсполнения.аргументы }
        var сведенияФайла = stat()
        guard lstat(корень.appendingPathComponent(имя).path, &сведенияФайла) == 0,
              сведенияФайла.st_mode & S_IFMT == S_IFREG, сведенияФайла.st_uid == geteuid(),
              сведенияФайла.st_mode & 0o077 == 0, сведенияФайла.st_size >= 0,
              сведенияФайла.st_size <= 1_048_576 else { throw ОшибкаКомандногоИсполнения.аргументы }
        let снимок = try НаблюдениеФайловойСистемы.наблюдать(корень: корень, источник: источник)
        guard снимок.записи.count == 1, let файл = снимок.записи.first,
              файл.путь == имя, файл.тип == .файл, let вход = файл.содержимое,
              вход.count <= 1_048_576 else { throw ОшибкаКомандногоИсполнения.аргументы }
        guard вход.reduce(0, { $0 + ($1 == 10 ? 1 : 0) }) <= 128 else {
            return try ответ("предел", отклонённыеБайтыСохранены: false)
        }
        let определение = try прочитатьВход(значения["--определение"]!, предел: 65_536)
        let программа = try ОпределениеОператора.разобрать(определение)
        guard программа.правила.isEmpty, программа.шаги.isEmpty else { throw ОшибкаКомандногоИсполнения.аргументы }
        let хэшПрограммы = хэшБайтовСреза(определение)
        let настройка: НастройкаВводаНаблюдения
        let путьСегмента = каталог.appendingPathComponent("сегмент.fumobs")
        if FileManager.default.fileExists(atPath: путьСегмента.path) {
            guard значения["--после"] != nil else { return try ответ("неизвестно", стадия: "существующая-история") }
            let читатель = try Сегмент(кореньДанных: каталог, запись: false, создать: false)
            defer { читатель.закрыть() }
            guard !читатель.естьХвост else { return try ответ("неизвестно", стадия: "хвост-истории") }
            guard let квитанция = читатель.записи.first(where: { $0.описание.идентификатор == "мост-jsonl-настройка" })
            else { throw ОшибкаКомандногоИсполнения.аргументы }
            настройка = try JSONDecoder().decode(НастройкаВводаНаблюдения.self,
                from: читатель.извлечь(квитанция.описание.идентификатор))
            guard настройка.источник == источник, настройка.поколение == поколение,
                  настройка.имяФайла == имя, настройка.хэшПрограммы == хэшПрограммы
            else { throw ОшибкаКомандногоИсполнения.аргументы }
            let адресМанифеста = настройка.приёмОпределения + "/манифест-JSONL"
            let манифест = try JSONDecoder().decode(МанифестПриёмаСреза.self,
                from: читатель.извлечь(адресМанифеста))
            guard манифест.приём == настройка.приёмОпределения,
                  манифест.исходноеОпределение.хэш == хэшПрограммы,
                  try читатель.квитанция(манифест.исходноеОпределение.описание.идентификатор) == манифест.исходноеОпределение,
                  try читатель.извлечь(манифест.исходноеОпределение.описание.идентификатор) == определение
            else { throw ОшибкаКомандногоИсполнения.расхождениеПовтора }
        } else {
            let приёмОпределения = UUID().uuidString.lowercased()
            настройка = НастройкаВводаНаблюдения(источник: источник, поколение: поколение,
                имяФайла: имя, хэшПрограммы: хэшПрограммы, приёмОпределения: приёмОпределения)
            do {
                let данные = try ИсполнениеСреза.принять(приём: приёмОпределения, вход: Data(),
                    определение: определение, каталог: каталог, операции: операции)
                let манифест = try JSONDecoder().decode(ОтветПриёмаСреза.self, from: данные)
                guard манифест.манифест.исходноеОпределение.хэш == хэшПрограммы else {
                    throw ОшибкаКомандногоИсполнения.расхождениеПовтора
                }
                try добавить(настройка, идентификатор: "мост-jsonl-настройка",
                    тип: "fuma.настройка-моста-jsonl.1", каталог: каталог, операции: операции)
            } catch { return try ответ("неизвестно", стадия: "настройка", приём: приёмОпределения) }
        }
        let цикл = ЦиклВводаJSONL()
        if let после = значения["--после"] {
            do {
                let читатель = try Сегмент(кореньДанных: каталог, запись: false, создать: false)
                defer { читатель.закрыть() }
                let адрес = "мост-пакет-" + после
                let квитанция = try читатель.квитанция(адрес)
                guard квитанция.описание.тип == "fuma.подтверждение-пакета-jsonl.1" else {
                    return try ответ("неизвестно", пакет: после, стадия: "подтверждение")
                }
                let подтверждение = try JSONDecoder().decode(ПодтверждениеПакетаНаблюдения.self,
                    from: читатель.извлечь(адрес))
                guard let предъявлено = значения["--подтверждение"], подтверждение.пакет == после,
                      подтверждение.хэшПрограммы == настройка.хэшПрограммы,
                      подтверждение.хэшПодтверждения == хэшБайтовСреза(Data(предъявлено.utf8)) else {
                    return try ответ("неизвестно", пакет: после, стадия: "подтверждение")
                }
                читатель.закрыть()
                let предыдущий = try цикл.прочитать(после, история: каталог)
                guard try подтверждённыеСвязи(пакет: после, рамки: предыдущий.рамки.map { ($0.начало, $0.конец, $0.sha256) },
                    хэшПрограммы: настройка.хэшПрограммы, каталог: каталог) != nil
                else { return try ответ("неизвестно", пакет: после, стадия: "неполная-связь") }
            } catch { return try ответ("неизвестно", пакет: после, стадия: "чтение-предыдущего") }
        }
        let исход: ИсходВводаJSONL
        do {
            исход = try цикл.принять(вход, источник: источник, поколение: поколение,
                после: значения["--после"], история: каталог, операции: операции)
        } catch { return try ответ("неизвестно", пакет: значения["--после"], стадия: "сверка-пакета") }
        let пакет: String
        let повтор: Bool
        switch исход {
        case .записано(let ссылка): пакет = ссылка.идентификатор; повтор = false
        case .повтор(let ссылка): пакет = ссылка; повтор = true
        case .дрейф: return try ответ("дрейф", отклонённыеБайтыСохранены: false)
        case .сменаИсточника: return try ответ("смена-источника", отклонённыеБайтыСохранены: false)
        case .предел: return try ответ("предел", отклонённыеБайтыСохранены: false)
        case let .неизвестныйИсход(идентификатор, хэш, диагностика):
            return try ответ("неизвестно", пакет: идентификатор, стадия: диагностика.стадия.rawValue, хэшПакета: хэш)
        }
        let запись: ПакетВводаJSONL
        do { запись = try цикл.прочитать(пакет, история: каталог) }
        catch { return try ответ("неизвестно", пакет: пакет, стадия: "чтение-пакета") }
        let рамки = запись.рамки.map { ($0.начало, $0.конец, $0.sha256) }
        if повтор {
            do {
                guard let связи = try подтверждённыеСвязи(пакет: пакет, рамки: рамки,
                    хэшПрограммы: настройка.хэшПрограммы, каталог: каталог)
                else { return try ответ("неизвестно", пакет: пакет, стадия: "неполная-связь") }
                return try ответ("повтор", пакет: пакет, связи: связи, подтверждение: значения["--подтверждение"])
            } catch { return try ответ("неизвестно", пакет: пакет, стадия: "чтение-связи") }
        }
        var связи: [СвязьРамкиНаблюдения] = []
        for (начало, конец, хэш) in рамки {
            let приём = UUID().uuidString.lowercased(), исполнение = UUID().uuidString.lowercased()
            let намерение = НамерениеРамкиНаблюдения(пакет: пакет, начало: начало, конец: конец,
                хэшРамки: хэш, хэшПрограммы: настройка.хэшПрограммы, приём: приём, исполнение: исполнение)
            var стадия = "намерение"
            do {
                guard начало >= 0, конец > начало, конец <= вход.count else { throw ОшибкаКомандногоИсполнения.аргументы }
                let байты = Data(вход[начало..<конец])
                guard хэшБайтовСреза(байты) == хэш else { throw ОшибкаКомандногоИсполнения.расхождениеПовтора }
                try добавить(намерение, идентификатор: "мост-намерение-" + исполнение,
                    тип: "fuma.намерение-рамки-jsonl.1", каталог: каталог, операции: операции)
                стадия = "приём"
                _ = try ИсполнениеСреза.принять(приём: приём, вход: байты, определение: определение,
                    каталог: каталог, операции: операции)
                стадия = "исполнение"
                let данные = try ИсполнениеСреза.исполнитьПринятый(приём: приём, исполнение: исполнение,
                    каталог: каталог, операции: операции)
                let результат = try JSONDecoder().decode(ОтветПринятогоСреза.self, from: данные)
                guard результат.запись.запись.отказ == nil, результат.запись.запись.рамки.count == 1,
                      результат.запись.запись.исходноеОпределение.хэш == настройка.хэшПрограммы,
                      результат.запись.запись.сыройВход.хэш == хэш
                else { throw ОшибкаКомандногоИсполнения.расхождениеПовтора }
                let связь = СвязьРамкиНаблюдения(пакет: пакет, начало: начало, конец: конец,
                    хэшРамки: хэш, хэшПрограммы: настройка.хэшПрограммы,
                    приём: приём, исполнение: исполнение, результат: результат.квитанция)
                стадия = "связь"
                try добавить(связь, идентификатор: "мост-связь-" + исполнение,
                    тип: "fuma.связь-рамки-jsonl.1", каталог: каталог, операции: операции)
                связи.append(связь)
            } catch {
                return try ответ("неизвестно", пакет: пакет, связи: связи, стадия: стадия,
                    приём: приём, исполнение: исполнение)
            }
        }
        let секретПодтверждения = UUID().uuidString.lowercased()
        let подтверждение = ПодтверждениеПакетаНаблюдения(пакет: пакет,
            хэшПодтверждения: хэшБайтовСреза(Data(секретПодтверждения.utf8)), хэшПрограммы: настройка.хэшПрограммы)
        do {
            try добавить(подтверждение, идентификатор: "мост-пакет-" + пакет,
                тип: "fuma.подтверждение-пакета-jsonl.1", каталог: каталог, операции: операции)
        } catch { return try ответ("неизвестно", пакет: пакет, связи: связи, стадия: "подтверждение-пакета") }
        return try ответ("записано", пакет: пакет, связи: связи, подтверждение: секретПодтверждения)
    }

    private static func добавить<T: Encodable>(_ значение: T, идентификатор: String, тип: String,
        каталог: URL, операции: ФайловыеОперации) throws {
        let писатель = try Сегмент(кореньДанных: каталог, запись: true, создать: false, операции: операции)
        defer { писатель.закрыть() }
        _ = try писатель.добавить(ОписаниеНаблюдения(идентификатор: идентификатор,
            тип: тип, источник: "FUMA"), данные: JSONEncoder().encode(значение))
    }

    private static func подтверждённыеСвязи(пакет: String, рамки: [(Int, Int, String)],
        хэшПрограммы: String, каталог: URL) throws -> [СвязьРамкиНаблюдения]? {
        let читатель = try Сегмент(кореньДанных: каталог, запись: false, создать: false)
        defer { читатель.закрыть() }
        guard !читатель.естьХвост else { return nil }
        let все = try читатель.записи.filter { $0.описание.тип == "fuma.связь-рамки-jsonl.1" }.map {
            try JSONDecoder().decode(СвязьРамкиНаблюдения.self, from: читатель.извлечь($0.описание.идентификатор))
        }.filter { $0.пакет == пакет }
        guard все.count == рамки.count else { return nil }
        var результат: [СвязьРамкиНаблюдения] = []
        for (начало, конец, хэш) in рамки {
            let подходящие = все.filter { $0.начало == начало && $0.конец == конец && $0.хэшРамки == хэш && $0.хэшПрограммы == хэшПрограммы }
            guard подходящие.count == 1, let связь = подходящие.first,
                  связь.исполнение == связь.результат.описание.идентификатор,
                  try читатель.квитанция(связь.результат.описание.идентификатор) == связь.результат
            else { return nil }
            let намерение = try JSONDecoder().decode(НамерениеРамкиНаблюдения.self,
                from: читатель.извлечь("мост-намерение-" + связь.исполнение))
            guard намерение == НамерениеРамкиНаблюдения(пакет: пакет, начало: начало, конец: конец,
                хэшРамки: хэш, хэшПрограммы: хэшПрограммы, приём: связь.приём,
                исполнение: связь.исполнение) else { return nil }
            let сохранено = try JSONDecoder().decode(ЗаписьПринятогоСреза.self,
                from: читатель.извлечь(связь.результат.описание.идентификатор))
            guard сохранено.манифест.описание.идентификатор == связь.приём + "/манифест-JSONL",
                  try читатель.квитанция(сохранено.манифест.описание.идентификатор) == сохранено.манифест,
                  сохранено.запись.отказ == nil, сохранено.запись.рамки.count == 1,
                  сохранено.запись.сыройВход.хэш == хэш,
                  сохранено.запись.исходноеОпределение.хэш == хэшПрограммы,
                  try читатель.квитанция(сохранено.запись.сыройВход.описание.идентификатор) == сохранено.запись.сыройВход,
                  try читатель.квитанция(сохранено.запись.исходноеОпределение.описание.идентификатор) == сохранено.запись.исходноеОпределение else { return nil }
            результат.append(связь)
        }
        return результат
    }

    private static func ответ(_ состояние: String, пакет: String? = nil,
        связи: [СвязьРамкиНаблюдения] = [], стадия: String? = nil, приём: String? = nil,
        исполнение: String? = nil, хэшПакета: String? = nil, подтверждение: String? = nil,
        отклонённыеБайтыСохранены: Bool? = nil) throws -> Data {
        try кодироватьСтрокуСреза(ОтветВводаНаблюдения(состояние: состояние, пакет: пакет,

import Foundation
import КонтейнерНаблюдений

/// Побочный эффект входного узла. Payload не декодируется и не нормализуется.
/// Два подтверждения последовательны: отказ может оставить только первый исходник.
enum ПриёмБайтов {
    private struct Происхождение: Encodable {
        let схема = "fuma.приём-байтов.1"
        let приём: String
        let часть: String
        let заявленныйИсточник: String
        let заявленныйТип: String
        let повторЗаписи: String?
    }

    static func сохранить(
        вход: Data, определение: Data, приём: String, источник: String,
        тип: String, время: String, повторЗаписи: String?, сегмент: Сегмент
    ) throws {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        func добавить(_ байты: Data, часть: String, источник: String, тип: String) throws {
            let сведения = Происхождение(приём: приём, часть: часть,
                заявленныйИсточник: источник, заявленныйТип: тип, повторЗаписи: повторЗаписи)
            let описание = ОписаниеНаблюдения(идентификатор: приём + "/" + часть,
                тип: "сырые-байты/" + часть, источник: "FUMA", время: время,
                спецификация: try кодировщик.encode(сведения))
            _ = try сегмент.добавить(описание, данные: байты)
        }
        try добавить(вход, часть: "вход-оператора", источник: источник, тип: тип)
        // Автор определения не выводится из заявленного автора входных данных.
        try добавить(определение, часть: "определение-оператора", источник: "неизвестно", тип: "байты")
    }
}

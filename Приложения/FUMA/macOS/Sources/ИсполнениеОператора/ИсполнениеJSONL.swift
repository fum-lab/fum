enum ИсполнениеСреза {
    static func выполнить(аргументы: [String], операции: ФайловыеОперации,
                          профиль: ((МеткаИсполнения) -> Void)?) throws -> Data {
        var значения: [String: String] = [:]
        var флаги = Set<String>()
        var номер = 0
        while номер < аргументы.count {
            let имя = аргументы[номер]
            if ["--исполнить-JSONL", "--профиль"].contains(имя) {
                guard флаги.insert(имя).inserted else { throw ОшибкаКомандногоИсполнения.аргументы }
                номер += 1
            } else {
                guard ["--определение", "--вход", "--журнал", "--повторить-JSONL"].contains(имя),
                      номер + 1 < аргументы.count, значения[имя] == nil,
                      !аргументы[номер + 1].isEmpty, !аргументы[номер + 1].hasPrefix("--")
                else { throw ОшибкаКомандногоИсполнения.аргументы }
                значения[имя] = аргументы[номер + 1]
                номер += 2
            }
        }
        guard let путь = значения["--журнал"] else { throw ОшибкаКомандногоИсполнения.аргументы }
        let каталог = try КомандноеИсполнениеОператора.проверитьКаталог(путь)
        if let идентификатор = значения["--повторить-JSONL"] {
            guard !флаги.contains("--исполнить-JSONL"), Set(значения.keys) == ["--повторить-JSONL", "--журнал"]
            else { throw ОшибкаКомандногоИсполнения.аргументы }
            return try повторить(идентификатор, каталог: каталог, операции: операции, профиль: профиль)
        }
        guard флаги.contains("--исполнить-JSONL"), Set(значения.keys) == ["--определение", "--вход", "--журнал"]
        else { throw ОшибкаКомандногоИсполнения.аргументы }
        return try исполнить(вход: прочитатьВход(значения["--вход"]!, предел: ПрофильСреза.текущий.байты),
            определение: прочитатьВход(значения["--определение"]!, предел: ПрофильСреза.текущий.определение),
            каталог: каталог, операции: операции, профиль: профиль)
    }

    static func исполнить(вход: Data, определение: Data, каталог: URL,
                          пределы: ПрофильСреза = .текущий,
                          операции: ФайловыеОперации = .системные,
                          профиль: ((МеткаИсполнения) -> Void)? = nil) throws -> Data {
        try пределы.проверить()
        guard вход.count <= пределы.байты, определение.count <= пределы.определение else { throw ОшибкаКонтейнера.предел }
        let каталог = try КомандноеИсполнениеОператора.проверитьКаталог(каталог.path)
        let приём = UUID().uuidString.lowercased()
        let время = ISO8601DateFormatter().string(from: Date())
        let сегмент = try Сегмент(кореньДанных: каталог, запись: true, операции: операции, профилировать: профиль != nil)
        defer { завершить(сегмент, профиль: профиль) }
        try измерить("сохранение-исходных-байтов", профиль: профиль) {
            try ПриёмБайтов.сохранить(вход: вход, определение: определение, приём: приём,
                источник: "неизвестно", тип: "JSONL", время: время, повторЗаписи: nil, сегмент: сегмент)
        }
        let сохранённыйПрофиль = try добавить(кодироватьСтрокуСреза(пределы), часть: "профиль-JSONL",
            приём: приём, время: время, сегмент: сегмент, профиль: профиль)
        let программа = try измерить("декодирование-определения", профиль: профиль) { try ОпределениеОператора.разобрать(определение) }
        let закрытие = try измерить("кодирование-замыкания", профиль: профиль) { try программа.данные() }
        guard закрытие.count <= пределы.определение else { throw ОшибкаКонтейнера.предел }
        let замыкание = try добавить(закрытие, часть: "замыкание-JSONL", приём: приём,
            время: время, сегмент: сегмент, профиль: профиль)
        guard let сырые = сегмент.записи.first(where: { $0.описание.идентификатор == приём + "/вход-оператора" }),
              let исходное = сегмент.записи.first(where: { $0.описание.идентификатор == приём + "/определение-оператора" })
        else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        let запись = try вычислить(вход: вход, программа: программа, пределы: пределы, сырые: сырые,
            исходное: исходное, замыкание: замыкание, сохранённыйПрофиль: сохранённыйПрофиль,
            приёмОтвета: приём, времяОтвета: время, профиль: профиль)
        return try сохранить(запись, приём: приём, время: время, сегмент: сегмент, профиль: профиль)
    }

    static func повторить(_ идентификатор: String, каталог: URL, операции: ФайловыеОперации = .системные,
                          профиль: ((МеткаИсполнения) -> Void)? = nil) throws -> Data {
        let каталог = try КомандноеИсполнениеОператора.проверитьКаталог(каталог.path)
        let сегмент = try Сегмент(кореньДанных: каталог, запись: true, создать: false,
            операции: операции, профилировать: профиль != nil)
        defer { завершить(сегмент, профиль: профиль) }
        guard let квитанция = сегмент.записи.first(where: { $0.описание.идентификатор == идентификатор }),
              квитанция.описание.тип == "исполнение-JSONL", квитанция.описание.версияСхемы == 1,
              квитанция.описание.источник == "FUMA", квитанция.размер <= 1_048_576
        else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        let данные = try сегмент.извлечь(идентификатор)
        let запись = try JSONDecoder().decode(ЗаписьСреза.self, from: данные)
        guard запись.схема == "fuma.исполнение-JSONL.1", try кодироватьСтрокуСреза(запись) == данные
        else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        try запись.профиль.проверить()
        guard данные.count <= запись.профиль.результат else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        let суффикс = "/вход-оператора"
        let имя = запись.сыройВход.описание.идентификатор
        guard имя.hasSuffix(суффикс) else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        let приём = String(имя.dropLast(суффикс.count))
        guard UUID(uuidString: приём)?.uuidString.lowercased() == приём else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        let вход = try извлечь(запись.сыройВход, идентификатор: приём + суффикс,
            тип: "сырые-байты/вход-оператора", предел: запись.профиль.байты, сегмент: сегмент)
        let исходное = try извлечь(запись.исходноеОпределение, идентификатор: приём + "/определение-оператора",
            тип: "сырые-байты/определение-оператора", предел: запись.профиль.определение, сегмент: сегмент)
        let закрытие = try извлечь(запись.замыкание, идентификатор: приём + "/замыкание-JSONL",
            тип: "замыкание-JSONL", предел: запись.профиль.определение, сегмент: сегмент)
        let профильБайты = try извлечь(запись.сохранённыйПрофиль, идентификатор: приём + "/профиль-JSONL",
            тип: "профиль-JSONL", предел: 65_536, сегмент: сегмент)
        guard try кодироватьСтрокуСреза(запись.профиль) == профильБайты else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        let программа = try ОпределениеОператора.разобрать(исходное)
        guard try программа.данные() == закрытие else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        let приёмОтвета = UUID().uuidString.lowercased()
        let времяОтвета = ISO8601DateFormatter().string(from: Date())
        let повтор = try измерить("replay", профиль: профиль) {
            try вычислить(вход: вход, программа: программа, пределы: запись.профиль, сырые: запись.сыройВход,
                исходное: запись.исходноеОпределение, замыкание: запись.замыкание,
                сохранённыйПрофиль: запись.сохранённыйПрофиль,
                приёмОтвета: приёмОтвета, времяОтвета: времяОтвета, профиль: профиль)
        }
        guard повтор == запись else { throw ОшибкаКомандногоИсполнения.расхождениеПовтора }
        return try сохранить(повтор, приём: приёмОтвета,
            время: времяОтвета, сегмент: сегмент, профиль: профиль)
    }

    private static func вычислить(вход: Data, программа: ОпределениеОператора, пределы: ПрофильСреза,
                                  сырые: Квитанция, исходное: Квитанция, замыкание: Квитанция,
                                  сохранённыйПрофиль: Квитанция, приёмОтвета: String, времяОтвета: String,
                                  профиль: ((МеткаИсполнения) -> Void)?) throws -> ЗаписьСреза {
        let рамки = try измерить("рамки-и-SHA", профиль: профиль) {
            try выделитьРамкиПотока(вход, пределы: ПределыРамокПотока(байты: пределы.байты, строка: пределы.строка, рамки: пределы.рамки))
        }
        func диапазон(_ начало: Int) -> ДиапазонСреза {
            ДиапазонСреза(начало: начало, конец: вход.count, хэшДиапазона: хэшБайтовСреза(Data(вход.dropFirst(начало))))
        }
        var запись = ЗаписьСреза(схема: "fuma.исполнение-JSONL.1", профиль: пределы, сыройВход: сырые,
            исходноеОпределение: исходное, замыкание: замыкание, сохранённыйПрофиль: сохранённыйПрофиль,
            рамки: [], границаСтрок: рамки.префикс,
            исполненныйПрефикс: try рамки.префикс(до: 0),
            сыройХвост: диапазон(рамки.префикс.байты), неИсполненныйСуффикс: диапазон(0),
            отказ: nil, учтеноОпераций: 0, записейТрассы: 0, трассаПолна: true)
        func размерОтвета(_ текущая: ЗаписьСреза) throws -> Int {
            try предельныйРазмерОтвета(текущая, приём: приёмОтвета, время: времяОтвета)
        }
        func резервОтказа(_ текущая: ЗаписьСреза, _ рамка: РамкаПотока) -> ЗаписьСреза {
            var резерв = текущая
            // Код отказа ограничен256 кодированными байтами; остальная форма известна.
            резерв.отказ = ОтказРамкиСреза(позиция: рамка.позиция, стадия: "сохранение-результата",
                код: String(repeating: "X", count: 253), выделеноОпераций: пределы.операции,
                выполненоОпераций: пределы.операции, учтеноОпераций: пределы.операции)
            резерв.учтеноОпераций = пределы.операции
            резерв.трассаПолна = false
            резерв.неИсполненныйСуффикс = диапазон(рамка.позиция.начало)
            return резерв
        }
        guard try размерОтвета(запись) <= пределы.результат else { throw ОшибкаКонтейнера.предел }
        for (индекс, рамка) in рамки.рамки.enumerated() {
            // До executor должно помещаться и конечное свидетельство его возможного отказа.
            let размерРезерва = try размерОтвета(резервОтказа(запись, рамка))
            guard размерРезерва <= пределы.результат else { throw ОшибкаКонтейнера.предел }
            let остаток = пределы.операции - запись.учтеноОпераций
            func отказ(_ стадия: String, _ код: String, выделено: Int, выполнено: Int?, учтено: Int) {
                запись.отказ = ОтказРамкиСреза(позиция: рамка.позиция, стадия: стадия, код: код,
                    выделеноОпераций: выделено, выполненоОпераций: выполнено, учтеноОпераций: учтено)
                запись.учтеноОпераций += учтено
                запись.неИсполненныйСуффикс = диапазон(рамка.позиция.начало)
            }
            let доступноВыхода = пределы.результат - размерРезерва
            guard остаток > 0, пределы.трасса - запись.записейТрассы >= программа.шаги.count,
                  доступноВыхода > 0 else {
                отказ("бюджет", "исчерпан-общий-бюджет", выделено: 0, выполнено: 0, учтено: 0)
                break
            }
            let значение: ЗначениеОператора
            do {
                значение = try измерить("декодирование", профиль: профиль) {
                    var проверка = ПроверкаРамкиСреза(рамка.данные, пределы: пределы)
                    try проверка.проверить()
                    return try КомандноеИсполнениеОператора.декодироватьВход(рамка.данные, вид: "текст", предел: пределы.строка)
                }
            } catch {
                отказ("декодирование", "неверный-JSON", выделено: 0, выполнено: 0, учтено: 0)
                break
            }
            let наблюдение: НаблюдениеОператора
            do {
                наблюдение = try измерить("исполнение", профиль: профиль) {
                    try AutomationExecutor.выполнить(программа, вход: значение, пределы: ПределыИсполнения(
                        байтовВхода: пределы.строка, байтовРезультата: доступноВыхода, операций: остаток,
                        записейТрассы: пределы.трасса - запись.записейТрассы - программа.шаги.count),
                        профиль: профиль == nil ? nil : { замер in
                            профиль?(МеткаИсполнения(стадия: "интерпретатор/" + замер.стадия,
                                наносекунды: замер.наносекунды, исход: замер.исход, глубина: 1))
                        })
                }
            } catch {
                запись.трассаПолна = false
                let код = (error as? ОшибкаИсполнения)?.код ?? "отказ-интерпретатора"
                let ограниченныйКод = (try? кодироватьСтрокуСреза(код).count) ?? Int.max
                отказ("исполнение", ограниченныйКод <= 256 ? код : "отказ-интерпретатора",
                    выделено: остаток, выполнено: nil, учтено: остаток)
                break
            }
            let данныеНаблюдения = try кодироватьСтрокуСреза(наблюдение)
            let числоТрассы = наблюдение.шаги.count + наблюдение.трасса.count + (наблюдение.применения?.count ?? 0)
            let полна = наблюдение.пропущеноЗаписей == 0 && (наблюдение.пропущеноПрименений ?? 0) == 0
            var кандидат = запись
            кандидат.рамки.append(ИсполненнаяРамкаСреза(позиция: рамка.позиция, выделеноОпераций: остаток,
                выполненоОпераций: наблюдение.выполненоОпераций, записейТрассы: числоТрассы,
                трассаПолна: полна, наблюдение: данныеНаблюдения, хэшНаблюдения: хэшБайтовСреза(данныеНаблюдения)))
            кандидат.учтеноОпераций += наблюдение.выполненоОпераций
            кандидат.записейТрассы += числоТрассы
            кандидат.трассаПолна = кандидат.трассаПолна && полна
            кандидат.исполненныйПрефикс = try рамки.префикс(до: рамка.позиция.номер)
            кандидат.неИсполненныйСуффикс = диапазон(рамка.позиция.конец)
            let следующий = индекс + 1 < рамки.рамки.count ? рамки.рамки[индекс + 1] : nil
            let сРезервом = следующий.map { резервОтказа(кандидат, $0) } ?? кандидат
            guard кандидат.учтеноОпераций <= пределы.операции, кандидат.записейТрассы <= пределы.трасса,
                  try размерОтвета(сРезервом) <= пределы.результат else {
                запись.трассаПолна = false
                отказ("сохранение-результата", "предел-кодированных-байтов", выделено: остаток,
                    выполнено: наблюдение.выполненоОпераций, учтено: наблюдение.выполненоОпераций)
                break
            }
            запись = кандидат
        }
        return запись
    }

    private static func извлечь(_ сохранённая: Квитанция, идентификатор: String, тип: String,
                                предел: Int, сегмент: Сегмент) throws -> Data {
        guard сохранённая.описание.идентификатор == идентификатор, сохранённая.описание.тип == тип,
              сохранённая.описание.версияСхемы == 1, сохранённая.описание.источник == "FUMA",
              сохранённая.размер <= UInt64(предел),
              сегмент.записи.first(where: { $0.описание.идентификатор == идентификатор }) == сохранённая
        else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        let данные = try сегмент.извлечь(идентификатор)
        guard данные.count == Int(сохранённая.размер), хэшБайтовСреза(данные) == сохранённая.хэш
        else { throw ОшибкаКомандногоИсполнения.записьПовтора }
        return данные
    }

    private static func добавить(_ данные: Data, часть: String, приём: String, время: String,
                                сегмент: Сегмент, профиль: ((МеткаИсполнения) -> Void)?) throws -> Квитанция {
        try измерить("сохранение-" + часть, профиль: профиль) {
            try сегмент.добавить(ОписаниеНаблюдения(идентификатор: приём + "/" + часть,
                тип: часть, источник: "FUMA", время: время, спецификация: Data("fuma.исполнение-JSONL.1".utf8)), данные: данные)
        }
    }

    private static func сохранить(_ запись: ЗаписьСреза, приём: String, время: String,
                                  сегмент: Сегмент, профиль: ((МеткаИсполнения) -> Void)?) throws -> Data {
        try измерить("сохранение-результата", профиль: профиль) {
            let данные = try кодироватьСтрокуСреза(запись)
            guard try предельныйРазмерОтвета(запись, приём: приём, время: время) <= запись.профиль.результат
            else { throw ОшибкаКонтейнера.предел }
            let квитанция = try сегмент.добавить(ОписаниеНаблюдения(идентификатор: приём,
                тип: "исполнение-JSONL", источник: "FUMA", время: время,
                спецификация: try кодироватьСтрокуСреза(запись.профиль)), данные: данные)
            let ответ = try кодироватьСтрокуСреза(ОтветСреза(схема: "fuma.результат-JSONL.1", квитанция: квитанция, запись: запись))
            guard ответ.count <= запись.профиль.результат else { throw ОшибкаКонтейнера.предел }
            return ответ
        }
    }

    /// Та же форма ответа, но максимальная разрядность размера и64 байта SHA.
    /// Будущие ID, время и спецификация уже известны; эта оценка не создаёт квитанцию.
    private static func предельныйРазмерОтвета(_ запись: ЗаписьСреза, приём: String, время: String) throws -> Int {
        struct ПредельнаяКвитанция: Encodable {
            let описание: ОписаниеНаблюдения
            let размер: UInt64
            let хэш: String
        }
        struct ПредельныйОтвет: Encodable {
            let схема: String
            let квитанция: ПредельнаяКвитанция
            let запись: ЗаписьСреза
        }
        let описание = ОписаниеНаблюдения(идентификатор: приём, тип: "исполнение-JSONL", источник: "FUMA",
            время: время, спецификация: try кодироватьСтрокуСреза(запись.профиль))
        return try кодироватьСтрокуСреза(ПредельныйОтвет(схема: "fuma.результат-JSONL.1",
            квитанция: ПредельнаяКвитанция(описание: описание, размер: UInt64(запись.профиль.результат),
                хэш: String(repeating: "0", count: 64)), запись: запись)).count
    }

    private static func завершить(_ сегмент: Сегмент, профиль: ((МеткаИсполнения) -> Void)?) {
        for метка in сегмент.профиль {
            профиль?(МеткаИсполнения(стадия: "контейнер/" + метка.этап, наносекунды: метка.наносекунды,
                исход: метка.исход, глубина: метка.глубина + 1))
        }
        сегмент.закрыть()
    }

    private static func измерить<Значение>(_ стадия: String, профиль: ((МеткаИсполнения) -> Void)?,
                                         _ действие: () throws -> Значение) rethrows -> Значение {
        let начало = DispatchTime.now().uptimeNanoseconds
        var исход = "отказ"
        defer { профиль?(МеткаИсполнения(стадия: стадия, наносекунды: DispatchTime.now().uptimeNanoseconds - начало, исход: исход, глубина: 0)) }
        let результат = try действие()
        исход = "успешно"
        return результат
    }
}

/// Закрытая синтаксическая граница до executor; никаких правил выбора сообщений.
/// Глубина считается от0, каждый JSON-узел учитывается до его разбора, как в графе.
private struct ПроверкаРамкиСреза {
    private let байты: [UInt8]
    private let пределы: ПрофильСреза
    private var позиция = 0
    private var узлы = 0

    init(_ данные: Data, пределы: ПрофильСреза) {
        байты = Array(данные)
        self.пределы = пределы
    }

    mutating func проверить() throws {
        guard String(bytes: байты, encoding: .utf8) != nil else { throw ОшибкаКомандногоИсполнения.кодировка }
        try значение(0)
        пробелы()
        guard позиция == байты.count else { throw ОшибкаКомандногоИсполнения.кодировка }
    }

    private mutating func пробелы() {
        while позиция < байты.count, [9, 10, 13, 32].contains(байты[позиция]) { позиция += 1 }
    }

    private mutating func принять(_ байт: UInt8) -> Bool {
        guard позиция < байты.count, байты[позиция] == байт else { return false }
        позиция += 1
        return true
    }

    private mutating func требовать(_ байт: UInt8) throws {
        пробелы()
        guard принять(байт) else { throw ОшибкаКомандногоИсполнения.кодировка }
    }

    private mutating func строка() throws -> String {
        пробелы()
        let начало = позиция
        try требовать(34)
        while позиция < байты.count {
            let байт = байты[позиция]
            позиция += 1
            if байт == 34 { return try JSONDecoder().decode(String.self, from: Data(байты[начало..<позиция])) }
            guard байт >= 32 else { throw ОшибкаКомандногоИсполнения.кодировка }
            if байт == 92 {
                guard позиция < байты.count else { throw ОшибкаКомандногоИсполнения.кодировка }
                позиция += 1
            }
        }
        throw ОшибкаКомандногоИсполнения.кодировка
    }

    private mutating func значение(_ глубина: Int) throws {
        guard глубина <= пределы.глубина, узлы < пределы.узлы else { throw ОшибкаКонтейнера.предел }
        узлы += 1
        пробелы()
        guard позиция < байты.count else { throw ОшибкаКомандногоИсполнения.кодировка }
        if принять(123) {
            var ключи = Set<String>()
            пробелы()
            if принять(125) { return }
            while true {
                let ключ = try строка()
                guard ключи.insert(ключ).inserted else { throw ОшибкаКомандногоИсполнения.кодировка }
                try требовать(58)
                try значение(глубина + 1)
                пробелы()
                if принять(125) { return }
                try требовать(44)
            }
        }
        if принять(91) {
            пробелы()
            if принять(93) { return }
            while true {
                try значение(глубина + 1)
                пробелы()
                if принять(93) { return }
                try требовать(44)
            }
        }
        if байты[позиция] == 34 { _ = try строка(); return }
        for слово in ["true", "false", "null"] {
            let часть = Array(слово.utf8)
            if байты[позиция...].starts(with: часть) { позиция += часть.count; return }
        }
        let начало = позиция
        _ = принять(45)
        guard позиция < байты.count else { throw ОшибкаКомандногоИсполнения.кодировка }
        if !принять(48) {
            guard (49...57).contains(байты[позиция]) else { throw ОшибкаКомандногоИсполнения.кодировка }
            while позиция < байты.count, (48...57).contains(байты[позиция]) { позиция += 1 }
        }
        guard Int64(String(decoding: байты[начало..<позиция], as: UTF8.self)) != nil else { throw ОшибкаКомандногоИсполнения.кодировка }
    }
}

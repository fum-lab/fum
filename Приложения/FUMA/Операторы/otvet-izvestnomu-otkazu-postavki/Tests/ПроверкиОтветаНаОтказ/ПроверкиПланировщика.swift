import Foundation
import Testing
@testable import ОтветНаОтказПоставки

struct ПроверкиПланировщика {
  private let ожидаемые = (1...13).map { "synthetic/allowed-\($0)" }
  private let лишние = (1...23).map { "synthetic/extra-\($0)" }

  private func запрос(
    отказ: ВидОтказа = .несовпадениеСоставаПоставки,
    остановка: String = "07d609",
    допускАктивен: Bool = true,
    ожидаемые: [String]? = nil,
    заявленные: [String]? = nil,
    фактические: [String]? = nil,
    базаДопуска: ОснованиеБазы = .токенФикстуры("922"),
    базаФакта: ОснованиеБазы = .токенФикстуры("922"),
    владелецФакта: String = "synthetic-owner",
    деревоФакта: String = "/synthetic/worktree",
    refФакта: String = "refs/heads/synthetic/stop-07d609",
    историяФакта: String = "synthetic-published-history",
    пауза: Bool = false,
    неизвестныйЭффект: Bool = false
  ) -> ЗапросОтвета {
    let имена = ожидаемые ?? self.ожидаемые
    return ЗапросОтвета(
      отказ: ТипизированныйОтказ(
        вид: отказ, идентификаторОстановки: остановка,
        заявленныеПути: заявленные ?? self.ожидаемые
      ),
      допуск: ДействующийДопуск(
        активен: допускАктивен, ожидаемыеПути: имена, база: базаДопуска,
        владелец: "synthetic-owner", рабочееДерево: "/synthetic/worktree",
        ссылкаВетки: "refs/heads/synthetic/stop-07d609",
        опубликованнаяИстория: "synthetic-published-history"
      ),
      состояние: НаблюдаемоеСостояние(
        фактическиеПутиРазличия: фактические ?? (self.ожидаемые + self.лишние),
        база: базаФакта, владелец: владелецФакта, рабочееДерево: деревоФакта,
        ссылкаВетки: refФакта, опубликованнаяИстория: историяФакта,
        действуетПауза: пауза, исходЭффектаНеизвестен: неизвестныйЭффект
      )
    )
  }

  private func ответ(_ запрос: ЗапросОтвета) throws -> ОтветОператора {
    try ОператорОтвета().сформироватьОтвет(запрос)
  }

  @Test func планВозвращаетРовноДвадцатьТриПутиИНеМеняетИсторию() throws {
    let ответ = try ответ(запрос())
    #expect(ответ.исход == .планИсправления)
    #expect(ответ.область == "синтетическая-фикстура-stop-07d609-13-36")
    #expect(ответ.эффектРазрешён == false)
    #expect(ответ.отправкаРазрешена == false)
    #expect(ответ.применимостьПодтверждена == false)
    #expect(ответ.причина == nil)
    #expect(ответ.план?.база == "922")
    #expect(ответ.план?.видОснованияБазы == "токен-фикстуры")
    #expect(ответ.план?.полныйИдентификаторОбъектаПодтверждён == false)
    #expect(ответ.план?.точныйМанифестПодтверждён == false)
    #expect(ответ.план?.применимостьПодтверждена == false)
    #expect(ответ.план?.общийОбработчикМанифеста == false)
    #expect(ответ.план?.владелец == "synthetic-owner")
    #expect(ответ.план?.рабочееДерево == "/synthetic/worktree")
    #expect(ответ.план?.ссылкаВетки == "refs/heads/synthetic/stop-07d609")
    #expect(ответ.план?.опубликованнаяИстория == "synthetic-published-history")
    #expect(ответ.план?.сохранитьПути == ожидаемые.sorted())
    #expect(ответ.план?.пути.map(\.путь) == лишние.sorted())
    #expect(ответ.план?.пути.allSatisfy { $0.действие == "вернуть-к-базе" } == true)
    #expect(ответ.план?.изменитьИсторию == false)
    #expect(ответ.план?.применениеРазрешено == false)
    #expect(ответ.план?.требуетсяПовторноеНаблюдение == true)
    #expect(ответ.эффект == "не-выполнять")
    #expect(ответ.черновикСообщения == (try self.ответ(запрос())).черновикСообщения)
  }

  @Test func исправленныйСоставДаётNoOp() throws {
    let ответ = try self.ответ(запрос(фактические: ожидаемые))
    #expect(ответ.исход == .ничегоНеДелать)
    #expect(ответ.эффектРазрешён == false)
    #expect(ответ.отправкаРазрешена == false)
    #expect(ответ.применимостьПодтверждена == false)
    #expect(ответ.план == nil)
    #expect(ответ.причина == nil)
    #expect(ответ.эффект == "не-выполнять")
  }

  @Test func полныйСинтетическийИдентификаторОбъектаОстаётсяЧистымПредложением() throws {
    let идентификаторОбъекта = String(repeating: "a", count: 40)
    let основание = ОснованиеБазы.полныйИдентификаторОбъекта(идентификаторОбъекта)
    let ответ = try self.ответ(запрос(базаДопуска: основание, базаФакта: основание))
    #expect(ответ.исход == .планИсправления)
    #expect(ответ.план?.база == идентификаторОбъекта)
    #expect(ответ.план?.видОснованияБазы == "полный-идентификатор-объекта")
    #expect(ответ.план?.полныйИдентификаторОбъектаПодтверждён == false)
    #expect(ответ.план?.точныйМанифестПодтверждён == false)
    #expect(ответ.план?.применимостьПодтверждена == false)
    #expect(ответ.план?.общийОбработчикМанифеста == false)
    #expect(ответ.план?.применениеРазрешено == false)
    #expect(ответ.план?.отправкаРазрешена == false)
  }

  @Test func одинаковыйТекстРазногоТипаОснованияЭскалируется() throws {
    let ответ = try self.ответ(запрос(
      базаДопуска: .токенФикстуры("922"), базаФакта: .полныйИдентификаторОбъекта(String(repeating: "a", count: 40))
    ))
    #expect(ответ.исход == .эскалация)
    #expect(ответ.причина == .другаяБаза)
    #expect(ответ.план == nil)
  }

  @Test func неполныйИдентификаторОбъектаНеПринимаетсяКакПолноеОснование() throws {
    let основание = ОснованиеБазы.полныйИдентификаторОбъекта("922")
    let ответ = try self.ответ(запрос(базаДопуска: основание, базаФакта: основание))
    #expect(ответ.исход == .эскалация)
    #expect(ответ.причина == .некорректныйИдентификаторОбъектаОснования)
    #expect(ответ.план == nil)
  }

  @Test(arguments: [
    ("другой отказ", ПричинаЭскалации.неизвестныйОтказ),
    ("другой владелец", ПричинаЭскалации.другойВладелец),
    ("другая база", ПричинаЭскалации.другаяБаза),
    ("другое дерево", ПричинаЭскалации.другоеРабочееДерево),
    ("другая ветка", ПричинаЭскалации.другаяВетка),
    ("другая история", ПричинаЭскалации.другаяОпубликованнаяИстория),
    ("пауза", ПричинаЭскалации.действуетПауза),
    ("неизвестный эффект", ПричинаЭскалации.неизвестныйИсходЭффекта),
    ("нет допуска", ПричинаЭскалации.нетДействующегоДопуска),
  ])
  func эскалацияНеФормируетПлан(имя: String, причина: ПричинаЭскалации) throws {
    let случай: ЗапросОтвета
    switch имя {
    case "другой отказ": случай = запрос(отказ: .другой)
    case "другой владелец": случай = запрос(владелецФакта: "foreign-owner")
    case "другая база": случай = запрос(базаФакта: .токенФикстуры("other-base"))
    case "другое дерево": случай = запрос(деревоФакта: "/foreign/worktree")
    case "другая ветка": случай = запрос(refФакта: "refs/heads/foreign")
    case "другая история": случай = запрос(историяФакта: "changed-history")
    case "пауза": случай = запрос(пауза: true)
    case "неизвестный эффект": случай = запрос(неизвестныйЭффект: true)
    default: случай = запрос(допускАктивен: false)
    }
    let ответ = try self.ответ(случай)
    #expect(ответ.исход == .эскалация, "\(имя)")
    #expect(ответ.причина == причина, "\(имя)")
    #expect(ответ.план == nil, "\(имя)")
    #expect(ответ.эффектРазрешён == false, "\(имя)")
    #expect(ответ.отправкаРазрешена == false, "\(имя)")
    #expect(ответ.применимостьПодтверждена == false, "\(имя)")
  }

  @Test func неизвестныйStopИНесовпадениеЗаявленногоСоставаЭскалируются() throws {
    #expect(try ответ(запрос(остановка: "another-stop")).причина == .неизвестныйОтказ)
    #expect(try ответ(запрос(заявленные: Array(ожидаемые.dropLast()))).причина == .ожидаемыйСоставНеСовпадает)
  }

  @Test func пропускПовторИНекорректныйПутьЭскалируются() throws {
    #expect(try ответ(запрос(фактические: Array(ожидаемые.dropLast()) + лишние)).причина == .заявленныйПутьОтсутствует)
    #expect(try ответ(запрос(фактические: ожидаемые + [ожидаемые[0]] + лишние)).причина == .повторныйПуть)
    #expect(try ответ(запрос(фактические: ожидаемые + ["../escape"] + лишние.dropFirst())).причина == .некорректныйПуть)
    #expect(try ответ(запрос(фактические: ожидаемые + ["synthetic/extra-one"])).причина == .неподдержанныйРазмерРазличия)
  }
}

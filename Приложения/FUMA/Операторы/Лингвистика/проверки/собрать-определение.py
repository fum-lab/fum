#!/usr/bin/env python3
"""Детерминированное предметное определение из закреплённой CC0-таблицы."""
import argparse
import hashlib
import json
from pathlib import Path

АЛФАВИТ = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
ХЭШ_ТАБЛИЦЫ = "ff1bfa5e1e3595789760376bf8600cb8a84b6e450906ca8b09706a7789d8fcd8"


def прочитать_таблицу(данные):
    if hashlib.sha256(данные).hexdigest() != ХЭШ_ТАБЛИЦЫ:
        raise ValueError("Таблица не совпала с закреплённым источником")
    источник = json.loads(данные)
    if источник["languageCode"] != "ru" or len(источник["table"]) != 53:
        raise ValueError("Неизвестный профиль таблицы")
    return источник["table"]


def составить_модель(исходные_ячейки):
    алфавит = set(АЛФАВИТ)
    отбор = {}
    классы = {}
    for индекс, ячейка in enumerate(исходные_ячейки):
        буква = ячейка["scriptElements"].get("Cyrl")
        if буква not in алфавит:
            continue
        if ячейка["prefixContext"] not in {"any", "consonant", "nonConsonant"}:
            raise ValueError("Неизвестный левый контекст первого среза")
        if ячейка["postfixContext"] not in {"any", "vowel", "nonVowel"}:
            raise ValueError("Неизвестный правый контекст первого среза")
        if ячейка["type"] not in {"consonant", "vowel", "other"}:
            raise ValueError("Неизвестный класс")
        классы.setdefault(буква, ячейка["type"])
        отбор.setdefault(буква, []).append({
            "индекс": индекс, "результат": ячейка["scriptElements"]["Latn"],
            "контекст-слева": ячейка["prefixContext"],
            "контекст-справа": ячейка["postfixContext"]
        })
    if set(отбор) != set(АЛФАВИТ) or sum(map(len, отбор.values())) != 40:
        raise ValueError("Нужны ровно 33 современные буквы и 40 исходных ячеек")
    таблица = {}
    for буква in АЛФАВИТ:
        ячейки = отбор[буква]
        индексы = {}
        for согласный in [False, True]:
            for гласный in [False, True]:
                подходящие = []
                for номер, ячейка in enumerate(ячейки):
                    левый = ячейка["контекст-слева"]
                    правый = ячейка["контекст-справа"]
                    слева = левый == "any" or согласный == (левый == "consonant")
                    справа = правый == "any" or гласный == (правый == "vowel")
                    if слева and справа:
                        подходящие.append(номер)
                if len(подходящие) != 1:
                    raise ValueError(f"Неоднозначная ячейка {буква}")
                индексы[согласный, гласный] = подходящие[0]
        шаг = индексы[False, True] - индексы[False, False]
        if шаг < 0 or any(индексы[с, г] != индексы[с, False] + (шаг if г else 0)
                         for с in [False, True] for г in [False, True]):
            raise ValueError(f"Контексты {буква} не представимы проверенной формулой")
        таблица[буква] = {
            "смещение-согласной": индексы[True, False],
            "смещение-несогласной": индексы[False, False],
            "шаг-гласной": шаг, "ячейки": ячейки
        }
    return классы, таблица


def литерал(значение):
    if значение is None:
        return ["null"]
    if isinstance(значение, bool):
        return ["истина" if значение else "ложь"]
    if isinstance(значение, list):
        return ["массив", *(литерал(часть) for часть in значение)]
    if isinstance(значение, dict):
        return {ключ: литерал(часть) for ключ, часть in значение.items()}
    return значение


def ссылка(имя):
    return ["переменная", имя]


def путь(значение, *ключи):
    return ["путь", значение, *ключи]


def вызов(место, имя, вход):
    return ["вызвать", место, имя, 1, вход]


def граф(переменные, результат):
    return {"схема": "fuma.граф-JSON.2", "числа": "целые64-без-дробей",
            "переменные": [{"имя": имя, "значение": значение}
                           for имя, значение in переменные], "результат": результат}


def определение(имя, вход, выход, переменные, результат):
    return {"идентификатор": имя, "версия": 1, "вход": вход, "выход": выход,
            "граф": граф(переменные, результат)}


def построить_определение(классы, таблица):
    определения = [
        определение("проверить-символ", "строка", "строка", [
            ("проверенная-длина", ["потребовать-диапазон", ["длина", ссылка("вход")], 1, 1])
        ], ссылка("вход")),
        определение("классифицировать-соседа", "JSON", "строка", [
            ("классы", литерал(классы))
        ], ["если", ["равно", ссылка("вход"), ["null"]], "nonLetter",
            путь(ссылка("классы"), вызов("символ-соседа", "проверить-символ", ссылка("вход")))]),
        определение("выбрать-ячейку", "объект", "объект", [
            ("буква", путь(ссылка("вход"), "буква")),
            ("слева", путь(ссылка("вход"), "слева")),
            ("справа", путь(ссылка("вход"), "справа")),
            ("количество-полей", ["потребовать-диапазон", ["длина", ссылка("вход")], 3, 3]),
            ("буква-проверена", вызов("целевая-буква", "проверить-символ", ссылка("буква"))),
            ("класс-слева", вызов("левый-сосед", "классифицировать-соседа", ссылка("слева"))),
            ("класс-справа", вызов("правый-сосед", "классифицировать-соседа", ссылка("справа"))),
            ("таблица", литерал(таблица)),
            ("ячейки-буквы", путь(ссылка("таблица"), ссылка("буква-проверена"))),
            ("смещение-слева", ["если", ["равно", ссылка("класс-слева"), "consonant"],
                путь(ссылка("ячейки-буквы"), "смещение-согласной"),
                путь(ссылка("ячейки-буквы"), "смещение-несогласной")]),
            ("смещение-справа", ["если", ["равно", ссылка("класс-справа"), "vowel"],
                путь(ссылка("ячейки-буквы"), "шаг-гласной"), 0]),
            ("номер", ["сложить", ссылка("смещение-слева"), ссылка("смещение-справа")]),
            ("ячейка", путь(ссылка("ячейки-буквы"), "ячейки", ссылка("номер")))
        ], {
            "результат": путь(ссылка("ячейка"), "результат"),
            "классы": {"слева": ссылка("класс-слева"), "справа": ссылка("класс-справа")},
            "индекс-ячейки": путь(ссылка("ячейка"), "индекс"),
            "контекст-ячейки": {"слева": путь(ссылка("ячейка"), "контекст-слева"),
                               "справа": путь(ссылка("ячейка"), "контекст-справа")}
        })
    ]
    return {"схема": "fum.определение-оператора.2", "идентификатор": "контекстная-транслитерация",
            "версия": 1, "правила": [], "определения": определения,
            "шаги": [{"идентификатор": "контекстная-ячейка", "оператор": "вычислить-JSON",
                       "аргументы": {"граф": граф([], вызов("выбор", "выбрать-ячейку", ссылка("вход")))}}]}


def сгенерировать(данные):
    классы, таблица = составить_модель(прочитать_таблицу(данные))
    документ = построить_определение(классы, таблица)
    return (json.dumps(документ, ensure_ascii=False, separators=(",", ":")) + "\n").encode()


def главная():
    разбор = argparse.ArgumentParser()
    разбор.add_argument("--проверить", action="store_true")
    вход = разбор.parse_args()
    предмет = Path(__file__).resolve().parent.parent
    данные = сгенерировать((предмет / "источник/ru.json").read_bytes())
    цель = предмет / "Определения/контекстная-ячейка.json"
    if вход.проверить:
        if цель.read_bytes() != данные:
            raise SystemExit("Определение не совпало с закреплённой генерацией")
    else:
        цель.write_bytes(данные)
    print(json.dumps({"букв": 33, "ячеек": 40, "байтов": len(данные),
                      "sha256": hashlib.sha256(данные).hexdigest()}, ensure_ascii=False))


if __name__ == "__main__":
    главная()

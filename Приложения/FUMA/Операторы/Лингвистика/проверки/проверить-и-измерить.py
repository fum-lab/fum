#!/usr/bin/env python3
"""Независимые фикстуры исполняются настоящим AutomationExecutor."""
import argparse
import hashlib
import json
import re
import subprocess
import statistics
from pathlib import Path


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode()


def отпечаток_эталона(предмет):
    копия = предмет.parents[3] / "Зависимости/LinguisticKit"
    def чтение(*аргументы):
        return subprocess.check_output(["git", "--no-optional-locks", *аргументы], cwd=копия)
    assert чтение("rev-parse", "HEAD").decode().strip() == "837e2ce107b97ee7b9d3344c9fe99142281fe393"
    assert not чтение("status", "--porcelain=v1", "--untracked-files=all")
    assert чтение("rev-parse", "--is-shallow-repository").strip() == b"false"
    return {x.decode(): hashlib.sha256((копия / x.decode()).read_bytes()).hexdigest()
            for x in чтение("ls-files", "-z").split(b"\0") if x}


def запустить(исполняемый, режим, определение, путь, работа, метка, повторы=1):
    команда = [str(исполняемый.resolve(strict=True)), режим, str(определение), str(путь), str(повторы)]
    if повторы > 1:
        команда.append("профиль")
    процесс = subprocess.run(команда, capture_output=True, timeout=120)
    (работа / (метка + ".stdout")).write_bytes(процесс.stdout)
    (работа / (метка + ".stderr")).write_bytes(процесс.stderr)
    assert процесс.returncode == 0, f"Harness {режим}: код {процесс.returncode}; полные каналы сохранены приватно"
    return json.loads(процесс.stdout)


def результаты_FUMA(наблюдение):
    результаты = []
    for запись in наблюдение["результаты"]:
        факт = запись["наблюдение"]["результат"]
        assert факт["тип"] == "текст"
        результаты.append(json.loads(факт["значение"])["результат"])
    return результаты


def сравнить_с_эталоном(факт, эталон):
    результаты = результаты_FUMA(факт)
    ожидаемые = [x["результат"] for x in эталон["результаты"]]
    assert len(результаты) == len(ожидаемые)
    assert [x.encode() for x in результаты] == [x.encode() for x in ожидаемые]
    return hashlib.sha256(байты(результаты)).hexdigest()


def главная():
    разбор = argparse.ArgumentParser()
    разбор.add_argument("режим", choices=["фикстуры", "профиль", "oracle", "полный-домен", "CLI-replay"])
    разбор.add_argument("--исполняемый", type=Path, required=True)
    разбор.add_argument("--каталог-работы", type=Path, required=True)
    разбор.add_argument("--выход", type=Path)
    разбор.add_argument("--fum", type=Path)
    разбор.add_argument("--определение", type=Path)
    вход = разбор.parse_args()
    предмет = Path(__file__).resolve().parent.parent
    работа = вход.каталог_работы.resolve(strict=True)
    assert not any((p / ".git").exists() for p in [работа, *работа.parents]), "Работа должна быть вне Git"
    определение = вход.определение or предмет / "Определения/контекстная-ячейка.json"
    хэш_определения = hashlib.sha256(определение.read_bytes()).hexdigest()
    хэш_исполняемого = hashlib.sha256(вход.исполняемый.read_bytes()).hexdigest()
    if вход.определение:
        assert вход.определение.resolve().parent == работа, "Сравниваемая копия должна быть приватной"
    фикстуры = json.loads((предмет / "фикстуры/ячейки.json").read_bytes())
    положительные = фикстуры["положительные"]
    отрицательные = фикстуры["отрицательные"]
    исходный_эталон = отпечаток_эталона(предмет) if вход.режим in ["oracle", "профиль", "полный-домен"] else None
    if вход.режим == "полный-домен":
        алфавит = tuple("абвгдеёжзийклмнопрстуфхцчшщъыьэюя")
        соседи = (None, *алфавит)
        хэши = []
        хэши_входов = []
        for номер, буква in enumerate(алфавит):
            строки = [байты({"буква": буква, "слева": слева, "справа": справа}).decode().rstrip("\n")
                      for слева in соседи for справа in соседи]
            путь = работа / f"пакет-{номер}.json"
            путь.write_bytes(байты(строки))
            хэши_входов.append(hashlib.sha256(путь.read_bytes()).hexdigest())
            факт = запустить(вход.исполняемый, "FUMA", определение, путь, работа, f"пакет-{номер}-FUMA")
            эталон = запустить(вход.исполняемый, "oracle", определение, путь, работа, f"пакет-{номер}-oracle")
            хэши.append(сравнить_с_эталоном(факт, эталон))
            print(json.dumps({"пакетов": номер + 1, "проверено": (номер + 1) * 1156}, ensure_ascii=False), flush=True)
        assert отпечаток_эталона(предмет) == исходный_эталон
        assert hashlib.sha256(вход.исполняемый.read_bytes()).hexdigest() == хэш_исполняемого
        assert hashlib.sha256(определение.read_bytes()).hexdigest() == хэш_определения
        итог = {"схема": "fum.linguistickit.полный-домен.1", "проверено": 38148,
                "пакетов": 33, "sha256-результатов-пакетов": хэши,
                "sha256-входов-пакетов": хэши_входов,
                "sha256-определения": хэш_определения, "sha256-harness": хэш_исполняемого,
                "граница": "Каждый результат сравнивается побайтно с прямым закреплённым Swift oracle; ожидаемые классы и ячейки здесь не вычисляются собственным кодом."}
        if вход.выход:
            assert вход.выход.resolve().parent == работа
            вход.выход.write_bytes(байты(итог))
        print(json.dumps({k: v for k, v in итог.items() if k not in ["sha256-результатов-пакетов", "sha256-входов-пакетов"]}, ensure_ascii=False))
        return
    if вход.режим == "CLI-replay":
        assert вход.fum is not None
        хэш_fum = hashlib.sha256(вход.fum.read_bytes()).hexdigest()
        журнал = работа / "runtime-журнал"
        журнал.mkdir(mode=0o700)
        копия = работа / "runtime-определение.json"
        файл_входа = работа / "runtime-вход.json"
        копия.write_bytes(определение.read_bytes())
        файл_входа.write_bytes(байты({"буква": "ъ", "слева": "б", "справа": "й"}))
        def вызвать(аргументы, метка):
            процесс = subprocess.run([str(вход.fum.resolve(strict=True)), *аргументы], capture_output=True, timeout=120)
            (работа / (метка + ".stdout")).write_bytes(процесс.stdout)
            (работа / (метка + ".stderr")).write_bytes(процесс.stderr)
            assert процесс.returncode == 0 and not процесс.stderr
            return json.loads(процесс.stdout)
        первый = вызвать(["--выполнить-оператор", "--определение", str(копия), "--вход", str(файл_входа),
                          "--тип-входа", "текст", "--журнал", str(журнал)], "CLI-первый")
        assert первый["схема"] == "fuma.результат-исполнения.1"
        assert json.loads(первый["наблюдение"]["результат"]["значение"])["результат"] == "yh"
        идентификатор = первый["квитанция"]["описание"]["идентификатор"]
        до = (журнал / "сегмент.fumobs").read_bytes()
        копия.unlink(); файл_входа.unlink()
        повтор = вызвать(["--повторить-оператор", идентификатор, "--журнал", str(журнал)], "CLI-повтор")
        assert повтор["схема"] == первый["схема"]
        assert повтор["наблюдение"] == первый["наблюдение"]
        for ключ in ["хэш", "размер"]:
            assert повтор["квитанция"][ключ] == первый["квитанция"][ключ]
        assert повтор["квитанция"]["описание"]["идентификатор"] != идентификатор
        после = (журнал / "сегмент.fumobs").read_bytes()
        assert после.startswith(до) and len(после) > len(до)
        assert hashlib.sha256(вход.fum.read_bytes()).hexdigest() == хэш_fum
        assert hashlib.sha256(определение.read_bytes()).hexdigest() == хэш_определения
        итог = {"схема": "fum.linguistickit.CLI-replay.1", "состояние": "успешно",
                "sha256-fum": хэш_fum, "sha256-определения": хэш_определения,
                "наблюдение": первый["наблюдение"]["хэшНаблюдения"], "префикс-сохранён": True,
                "источники-удалены-до-повтора": True}
        if вход.выход:
            assert вход.выход.resolve().parent == работа
            вход.выход.write_bytes(байты(итог))
        print(json.dumps(итог, ensure_ascii=False))
        return
    строки = [байты(x["вход"]).decode().rstrip("\n") for x in положительные]
    if вход.режим == "фикстуры":
        строки += [x.get("сырой-вход") or байты(x["вход"]).decode().rstrip("\n") for x in отрицательные]
    elif вход.режим == "профиль":
        строки = строки[:40]
    путь = работа / ("входы-" + вход.режим + ".json")
    путь.write_bytes(байты(строки))
    режимы = ["FUMA", "oracle"] if вход.режим in ["oracle", "профиль"] else ["FUMA"]
    if вход.режим == "профиль":
        режимы = [режим for номер in range(6)
                  for режим in (["FUMA", "oracle"] if номер % 2 == 0 else ["oracle", "FUMA"])]
    наблюдения = []
    for номер, режим in enumerate(режимы):
        наблюдения.append(запустить(вход.исполняемый, режим, определение, путь, работа,
                                   вход.режим + "-" + str(номер) + "-" + режим,
                                   6 if вход.режим == "профиль" else 1))
    if вход.режим in ["фикстуры", "oracle", "профиль"]:
        записи = наблюдения[0]["результаты"]
        assert len(записи) == len(строки)
        for номер, пример in enumerate(положительные[:len(строки)]):
            факт = записи[номер]["наблюдение"]
            assert факт["результат"]["тип"] == "текст"
            assert json.loads(факт["результат"]["значение"]) == пример["ожидается"], f"Результат ячейки {номер}"
            assert факт["результат"]["значение"] == байты(пример["ожидается"]).decode().rstrip("\n")
            assert факт["пропущеноПрименений"] == 0
            assert факт["пропущеноЗаписей"] == 0
            выборы = [x for x in факт["применения"] if x["определение"] == "выбрать-ячейку"]
            assert len(выборы) == 1
            assert json.loads(выборы[0]["результатJSON"]) == пример["ожидается"]
            классы = [x for x in факт["применения"] if x["определение"] == "классифицировать-соседа"]
            assert len(классы) == 2
            for сторона, место in [("слева", "левый-сосед"), ("справа", "правый-сосед")]:
                следы = [x for x in классы if x["место"] == место]
                assert len(следы) == 1
                assert следы[0]["родитель"] == выборы[0]["экземпляр"]
                assert json.loads(следы[0]["входJSON"]) == пример["вход"][сторона]
                assert json.loads(следы[0]["результатJSON"]) == пример["ожидается"]["классы"][сторона]
            assert re.fullmatch(r"sha256:[0-9a-f]{64}", факт["хэшНаблюдения"])
        if вход.режим == "фикстуры":
            for номер, пример in enumerate(отрицательные, len(положительные)):
                assert записи[номер] == {"ошибка": пример["ошибка"]}, f"Отказ {номер}: {записи[номер]}"
            повтор = запустить(вход.исполняемый, "FUMA", определение, путь, работа, "фикстуры-повтор")
            assert повтор["результаты"] == записи, "Повтор наблюдений отличается"
        elif вход.режим == "oracle":
            эталоны = наблюдения[1]["результаты"]
            for номер, пример in enumerate(положительные):
                assert эталоны[номер]["результат"] == пример["ожидается"]["результат"]
        else:
            for номер in range(0, len(наблюдения), 2):
                пара = наблюдения[номер:номер + 2]
                факт = next(x for x in пара if x["режим"] == "FUMA")
                эталон = next(x for x in пара if x["режим"] == "oracle")
                сравнить_с_эталоном(факт, эталон)
            for наблюдение in наблюдения:
                хэши = наблюдение["sha256-результатов-раундов"]
                assert len(хэши) == 6 and len(set(хэши)) == 1, "Результаты профильных раундов отличаются"
                наблюдение.pop("результаты")
    if исходный_эталон is not None:
        assert отпечаток_эталона(предмет) == исходный_эталон
    assert hashlib.sha256(вход.исполняемый.read_bytes()).hexdigest() == хэш_исполняемого
    assert hashlib.sha256(определение.read_bytes()).hexdigest() == хэш_определения
    результат = {
        "схема": "fum.linguistickit.проверка.1", "режим": вход.режим,
        "состояние": "успешно", "входов": len(строки),
        "sha256-набора": hashlib.sha256(путь.read_bytes()).hexdigest(),
        "sha256-определения": хэш_определения,
        "наблюдения": наблюдения if вход.режим == "профиль" else [],
        "oracle": "выполнен" if вход.режим in ["oracle", "профиль"] else "не выполнен",
        "sha256-harness": хэш_исполняемого,
        "CLI-и-replay": "не выполнены; повтор harness не подменяет runtime replay"
    }
    if вход.режим == "профиль":
        медианы = {режим: statistics.median(нс for x in наблюдения if x["режим"] == режим
                                           for нс in x["повторные-наборы-нс"])
                   for режим in ["FUMA", "oracle"]}
        результат["медианы-тёплого-набора-нс"] = медианы
        результат["отношение-времени-FUMA-к-oracle"] = медианы["FUMA"] / медианы["oracle"]
    if вход.выход:
        выход = вход.выход.resolve()
        assert выход.parent == работа, "Результат сначала сохраняется только приватно"
        выход.write_bytes(байты(результат))
    print(json.dumps({k: v for k, v in результат.items() if k != "наблюдения"}, ensure_ascii=False))


if __name__ == "__main__":
    главная()

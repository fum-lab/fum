#!/usr/bin/env python3
"""Проверить настоящий SwiftPM-манифест из разных каталогов и измерить его разбор.

Все фикстуры, кэши и сырые каналы сохраняются в явно заданном приватном каталоге.
Режим проверки не выполняет предметные фикстуры транслитерации. Профиль сравнивает
две версии манифеста в одном пакете, с одинаковой командой и разобранным результатом.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import resource
import shutil
import statistics
import subprocess
import time

ПУТЬ_ПАКЕТА = Path("Приложения/FUMA/Операторы/Лингвистика/проверки")
ПУТЬ_ПАМЯТИ = Path("Прототипы/память-структурирующих-операторов")
ПУТЬ_ЭТАЛОНА = Path("Зависимости/LinguisticKit")
ОШИБКА_КОРНЯ = "FUM: неверный корень пакета"


def хэш(байты: bytes) -> str:
    return hashlib.sha256(байты).hexdigest()


def сохранить(путь: Path, данные: object) -> None:
    путь.write_text(json.dumps(данные, ensure_ascii=False, indent=2) + "\n")


def запретить_дамп() -> None:
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))


def подготовить(корень: Path, исходник: bytes, репозиторий: Path,
                *, память: bool = True, эталон: bool = False) -> Path:
    пакет = корень / ПУТЬ_ПАКЕТА
    пакет.mkdir(parents=True)
    (пакет / "Package.swift").write_bytes(исходник)
    for имя in ("AGENTS.md", ".gitmodules"):
        (корень / имя).write_bytes((репозиторий / имя).read_bytes())
    for относительный, нужен in ((ПУТЬ_ПАМЯТИ, память), (ПУТЬ_ЭТАЛОНА, эталон)):
        if нужен:
            назначение = корень / относительный
            назначение.mkdir(parents=True)
            (назначение / "Package.swift").write_bytes(
                (репозиторий / относительный / "Package.swift").read_bytes())
    return пакет


def выполнить(пакет: Path, рабочий_каталог: Path, каталог: Path,
              компилятор: str, номер: int) -> tuple[dict | None, dict]:
    окружение = os.environ.copy()
    окружение["CLANG_MODULE_CACHE_PATH"] = str(каталог / "модули")
    окружение["SWIFTPM_MODULECACHE_OVERRIDE"] = str(каталог / "модули")
    команда = [компилятор, "package", "--package-path", str(пакет),
               "--scratch-path", str(каталог / "сборка"),
               "--cache-path", str(каталог / "кэш"),
               "--config-path", str(каталог / "настройки"),
               "--security-path", str(каталог / "безопасность"),
               "--disable-sandbox", "dump-package"]
    начало = time.perf_counter_ns()
    процесс = subprocess.run(команда, cwd=рабочий_каталог, env=окружение,
                             capture_output=True, timeout=120,
                             preexec_fn=запретить_дамп)
    длительность = time.perf_counter_ns() - начало
    for суффикс, байты in (("stdout", процесс.stdout), ("stderr", процесс.stderr)):
        (каталог / f"{номер}.{суффикс}").write_bytes(байты)
    данные = json.loads(процесс.stdout) if процесс.returncode == 0 else None
    наблюдение = {"код": процесс.returncode, "наносекунды": длительность,
                  "stdout_sha256": хэш(процесс.stdout),
                  "stderr_sha256": хэш(процесс.stderr),
                  "маркер_корня": ОШИБКА_КОРНЯ in процесс.stderr.decode(errors="replace")}
    if данные is not None:
        наблюдение["JSON_sha256"] = хэш(json.dumps(
            данные, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode())
    return данные, наблюдение


def проверить_пакет(данные: dict | None, корень: Path, эталон: bool) -> None:
    assert данные is not None, "положительный манифест не разобран"
    зависимости = [запись["fileSystem"][0]["path"] for запись in данные["dependencies"]]
    ожидаемые = [str(корень / ПУТЬ_ПАМЯТИ)]
    if эталон:
        ожидаемые.append(str(корень / ПУТЬ_ЭТАЛОНА))
    assert зависимости == ожидаемые, "неверные пути зависимостей"
    цель = данные["targets"][0]
    продукты = [запись["product"][0] for запись in цель["dependencies"]]
    assert продукты == (["FUMStructuringOperatorMemory", "LinguisticKit.static"]
                        if эталон else ["FUMStructuringOperatorMemory"])
    определения = [запись["kind"]["define"]["_0"] for запись in цель["settings"]
                   if "define" in запись["kind"]]
    assert определения == (["LINGUISTICKIT_ORACLE"] if эталон else [])


def проверить(репозиторий: Path, каталог: Path, компилятор: str) -> dict:
    исходник = (репозиторий / ПУТЬ_ПАКЕТА / "Package.swift").read_bytes()
    посторонний = каталог / "посторонний-cwd"
    посторонний.mkdir()
    случаи = []
    ошибки = []

    def случай(имя: str, пакет: Path, рабочий: Path, ожидание) -> dict | None:
        данные, наблюдение = выполнить(пакет, рабочий, каталог, компилятор, len(случаи))
        наблюдение["случай"] = имя
        try:
            ожидание(данные, наблюдение)
            наблюдение["проверено"] = True
        except AssertionError as ошибка:
            наблюдение["проверено"] = False
            ошибки.append({"случай": имя, "ошибка": str(ошибка)})
        случаи.append(наблюдение)
        return данные

    def положительный(корень: Path, эталон: bool):
        return lambda данные, наблюдение: проверить_пакет(данные, корень, эталон)

    def отрицательный(данные, наблюдение):
        assert наблюдение["код"] != 0 and наблюдение["маркер_корня"], \
            "нет собственного закрытого отказа неверного корня"

    есть_эталон = (репозиторий / ПУТЬ_ЭТАЛОНА / "Package.swift").is_file()
    первый = случай("настоящий-пакет-из-корня", репозиторий / ПУТЬ_ПАКЕТА,
                    репозиторий, положительный(репозиторий, есть_эталон))
    второй = случай("настоящий-пакет-из-другого-cwd", репозиторий / ПУТЬ_ПАКЕТА,
                    посторонний, положительный(репозиторий, есть_эталон))
    if первый != второй:
        ошибки.append({"случай": "другой-cwd", "ошибка": "JSON отличается"})
    for имя, эталон in (("без-эталона", False), ("с-эталоном", True)):
        корень = каталог / имя
        пакет = подготовить(корень, исходник, репозиторий, эталон=эталон)
        случай(имя, пакет, посторонний, положительный(корень, эталон))
    корень = каталог / "без-обязательной-памяти"
    пакет = подготовить(корень, исходник, репозиторий, память=False)
    случай("нет-обязательной-памяти", пакет, посторонний, отрицательный)
    корень = каталог / "без-маркера"
    пакет = подготовить(корень, исходник, репозиторий)
    (корень / "AGENTS.md").unlink()
    случай("нет-маркера", пакет, посторонний, отрицательный)
    корень = каталог / "без-gitmodules"
    пакет = подготовить(корень, исходник, репозиторий)
    (корень / ".gitmodules").unlink()
    случай("нет-gitmodules", пакет, посторонний, отрицательный)
    корень = каталог / "манифест-памяти-каталог"
    пакет = подготовить(корень, исходник, репозиторий)
    манифест = корень / ПУТЬ_ПАМЯТИ / "Package.swift"
    манифест.unlink()
    манифест.mkdir()
    случай("манифест-памяти-не-файл", пакет, посторонний, отрицательный)
    корень = каталог / "неверная-структура"
    верный_пакет = подготовить(корень, исходник, репозиторий)
    пакет = верный_пакет.parent / "неверные-проверки"
    пакет.mkdir()
    (верный_пакет / "Package.swift").rename(пакет / "Package.swift")
    случай("неверная-структура", пакет, посторонний, отрицательный)

    def отсутствующий(данные, наблюдение):
        assert наблюдение["код"] != 0, "SwiftPM принял отсутствующий каталог"

    случай("нет-каталога-пакета", каталог / "отсутствует", посторонний, отсутствующий)
    return {"схема": "fum.проверка-корня-лингвистики.1",
            "манифест_sha256": хэш(исходник), "случаи": случаи, "ошибки": ошибки}


def профиль(репозиторий: Path, каталог: Path, компилятор: str, исходный: Path) -> dict:
    версии = {"до": исходный.read_bytes(),
              "после": (репозиторий / ПУТЬ_ПАКЕТА / "Package.swift").read_bytes()}
    корень = каталог / "вход"
    пакет = подготовить(корень, версии["до"], репозиторий, эталон=True)
    рабочий = каталог / "посторонний-cwd"
    рабочий.mkdir()
    записи = []
    наблюдаемые = []
    порядок = [(версия, True) for версия in версии]
    порядок += [(версия, False) for пара in range(6)
                for версия in (("до", "после") if пара % 2 == 0 else ("после", "до"))]
    for номер, (версия, прогрев) in enumerate(порядок):
        (пакет / "Package.swift").write_bytes(версии[версия])
        данные, запись = выполнить(пакет, рабочий, каталог, компилятор, номер)
        проверить_пакет(данные, корень, True)
        наблюдаемые.append(данные)
        запись.update({"версия": версия, "прогрев": прогрев})
        записи.append(запись)
    assert all(данные == наблюдаемые[0] for данные in наблюдаемые), "разобранный JSON изменился"
    версия_swift = subprocess.check_output([компилятор, "--version"], text=True).strip()
    return {"схема": "fum.профиль-корня-лингвистики.1",
            "swift": версия_swift, "вход": str(ПУТЬ_ПАКЕТА),
            "argv_одинаков": True, "cwd_одинаков": True,
            "разобранный_JSON_равен": True,
            "манифесты_sha256": {имя: хэш(байты) for имя, байты in версии.items()},
            "замеры": записи,
            "медианы_наносекунды": {имя: statistics.median(
                запись["наносекунды"] for запись in записи
                if запись["версия"] == имя and not запись["прогрев"]) for имя in версии}}


def главная() -> int:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("режим", choices=("проверить", "профиль"))
    разбор.add_argument("--корень-репозитория", type=Path, required=True)
    разбор.add_argument("--каталог-работы", type=Path, required=True)
    разбор.add_argument("--компилятор-swift", default=shutil.which("swift"))
    разбор.add_argument("--исходный-манифест", type=Path)
    разбор.add_argument("--выход", type=Path, required=True)
    аргументы = разбор.parse_args()
    каталог = аргументы.каталог_работы.resolve()
    if каталог.exists():
        разбор.error("Нужен новый приватный каталог работы")
    if any((предок / ".git").exists() for предок in (каталог, *каталог.parents)):
        разбор.error("Каталог работы должен находиться вне Git")
    каталог.mkdir(mode=0o700)
    if аргументы.режим == "профиль":
        if аргументы.исходный_манифест is None:
            разбор.error("Для профиля нужен исходный манифест")
        результат = профиль(аргументы.корень_репозитория.resolve(), каталог,
                            аргументы.компилятор_swift, аргументы.исходный_манифест)
    else:
        результат = проверить(аргументы.корень_репозитория.resolve(), каталог,
                              аргументы.компилятор_swift)
    сохранить(аргументы.выход, результат)
    print(json.dumps({"схема": результат["схема"],
                      "ошибок": len(результат.get("ошибки", [])),
                      "выход_sha256": хэш(аргументы.выход.read_bytes())}, ensure_ascii=False))
    return 1 if результат.get("ошибки") else 0


if __name__ == "__main__":
    raise SystemExit(главная())

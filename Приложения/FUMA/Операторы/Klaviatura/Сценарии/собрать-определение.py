"""Собрать чистый переход FUMA v1 из точной таблицы; фикстуры не читаются."""
import argparse
import json
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]


def собрать(таблица):
    переменные = []

    def узел(имя, значение):
        переменные.append({'имя': имя, 'значение': значение})
        return ['переменная', имя]

    def либо(а, б):
        return ['если', а, ['истина'], б]

    def вместе(а, б):
        return ['если', а, б, ['ложь']]

    def нет(а):
        return ['если', а, ['ложь'], ['истина']]

    узел('число-полей-входа', ['потребовать-диапазон', ['длина', ['переменная', 'вход']], 4, 4])
    клавиша = узел('клавиша', ['потребовать-диапазон', ['путь', ['переменная', 'вход'], 'клавиша'], -9223372036854775808, 9223372036854775807])
    фаза = узел('фаза', ['соединить', ['путь', ['переменная', 'вход'], 'фаза']])
    повтор = узел('повтор', ['если', ['путь', ['переменная', 'вход'], 'повтор'], ['истина'], ['ложь']])
    прежнее = узел('прежнее', ['путь', ['переменная', 'вход'], 'модификаторы'])
    узел('число-полей-состояния', ['потребовать-диапазон', ['длина', прежнее], 7, 7])
    старые = {имя: узел('старый-' + имя, ['если', ['путь', прежнее, имя], ['истина'], ['ложь']])
        for имя in [*таблица['модификаторы'].values(), 'смешанная_последовательность']}
    нажатие = узел('нажатие', ['равно', фаза, 'нажатие'])
    отпускание = узел('отпускание', ['равно', фаза, 'отпускание'])
    прикосновение = узел('прикосновение', ['равно', фаза, 'прикосновение'])
    допустимая = узел('допустимая-фаза', либо(нажатие, либо(отпускание, прикосновение)))
    кодКоманды = таблица['команда']['клавиша']
    коды = [int(кодТаблицы) for кодТаблицы in таблица['текстовые_клавиши']] + [кодКоманды] + [int(кодТаблицы) for кодТаблицы in таблица['модификаторы']]
    def присутствует(имена):
        return нет(['равно', ['сумма', ['отобразить', ['массив', *имена], 'код', ['если', ['равно', клавиша, ['переменная', 'код']], 1, 0]]], 0])
    известна = узел('известная-клавиша', присутствует(коды))
    модификатор = узел('модификатор', присутствует([int(кодТаблицы) for кодТаблицы in таблица['модификаторы']]))
    меняется = узел('меняется-состояние', вместе(известна, вместе(модификатор, вместе(либо(нажатие, отпускание), нет(повтор)))))
    стороны = {}
    for код, имя in таблица['модификаторы'].items():
        стороны[имя] = узел('новый-' + имя, ['если', вместе(меняется, ['равно', клавиша, int(код)]), нажатие, старые[имя]])
    сдвиг = узел('сдвиг', либо(стороны['сдвиг_слева'], стороны['сдвиг_справа']))
    опция = узел('опция', либо(стороны['опция_слева'], стороны['опция_справа']))
    команда = узел('команда', либо(стороны['команда_слева'], стороны['команда_справа']))
    смешаны = узел('смешаны', ['если', меняется, ['если', либо(сдвиг, опция), либо(старые['смешанная_последовательность'], вместе(сдвиг, опция)), ['ложь']], старые['смешанная_последовательность']])
    состояние = узел('состояние', {**стороны, 'смешанная_последовательность': смешаны})
    удалить = узел('удалить', ['равно', клавиша, кодКоманды])
    # Последовательные узлы ограничивают глубину JSON; порядок здесь — от меньшего приоритета к большему.
    исход = узел('исход-0', ['если', удалить, 'команда', 'текст'])
    for номер, условие, текст in [(1, вместе(повтор, нет(удалить)), 'повтор-подавлен'), (2, либо(смешаны, вместе(сдвиг, опция)), 'смешанные-модификаторы'), (3, команда, 'командное-сочетание'), (4, отпускание, 'отпускание'), (5, модификатор, ['если', повтор, 'повтор-подавлен', ['если', отпускание, 'отпускание', 'модификатор']]), (6, прикосновение, 'прикосновение'), (7, нет(допустимая), 'недопустимая-фаза'), (8, нет(известна), 'неизвестная-клавиша')]:
        исход = узел('исход-' + str(номер), ['если', условие, текст, исход])
    отказ = узел('отказ', либо(['равно', исход, 'неизвестная-клавиша'], либо(['равно', исход, 'недопустимая-фаза'], либо(['равно', исход, 'командное-сочетание'], ['равно', исход, 'смешанные-модификаторы']))))
    текст = узел('текст', ['равно', исход, 'текст'])
    слой = узел('слой', ['если', отказ, 'неподдержано', ['если', текст, ['если', сдвиг, 'сдвиг', ['если', опция, 'опция', 'базовый']], 'нет']])
    данные = узел('таблица', таблица['текстовые_клавиши'])
    результат = {'статус': ['если', отказ, 'неподдержано', 'поддержано'],
        'вывод': {'вид': ['если', текст, 'текст', ['если', ['равно', исход, 'команда'], 'команда', 'нет']],
                  'значение': ['если', текст, ['путь', данные, ['в-строку', клавиша], слой], ['если', ['равно', исход, 'команда'], таблица['команда']['значение'], '']]},
        'модификаторы': состояние,
        'трасса': {'оператор': 'переход-раскладки-Klaviatura', 'версия': 1, 'клавиша': клавиша, 'фаза': фаза, 'повтор': повтор, 'слой': слой, 'исход': исход}}
    return {'схема': 'fum.определение-оператора.1', 'идентификатор': 'переход-раскладки-Klaviatura', 'версия': 1, 'правила': [], 'шаги': [{'идентификатор': 'переход-раскладки', 'оператор': 'вычислить-JSON', 'аргументы': {'граф': {'схема': 'fuma.граф-JSON.1', 'числа': 'целые64-без-дробей', 'переменные': переменные, 'результат': результат}}}]}


def основная():
    параметры = argparse.ArgumentParser()
    параметры.add_argument('--проверить', action='store_true')
    выбор = параметры.parse_args()
    таблица = json.loads((КОРЕНЬ / 'таблица-раскладки.json').read_text())
    данные = (json.dumps(собрать(таблица), ensure_ascii=False, indent=2) + '\n').encode()
    файл = КОРЕНЬ / 'определение.json'
    if выбор.проверить:
        if файл.read_bytes() != данные:
            raise SystemExit('Определение расходится с таблицей и генератором')
    else:
        файл.write_bytes(данные)


if __name__ == '__main__':
    основная()

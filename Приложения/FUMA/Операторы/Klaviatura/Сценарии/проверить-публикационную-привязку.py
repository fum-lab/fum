"""Настоящие Swift-запуски: явный корень, другой рабочий каталог и закрытые отказы."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import time

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПЕРЕМЕННАЯ_КОРНЯ = 'КЛАВИАТУРА_КОРЕНЬ_ПАКЕТА'
ИСХОДНИКИ = ['Tests/ПроверкиКлавиатуры/ПроверкиПереходов.swift',
             'Проверки/проверить-и-измерить.py', 'Сценарии/проверить-публикационную-привязку.py']
ИМЕНА_ВЫЗОВОВ = ['Явный корень из другого рабочего каталога', 'Отсутствующий корень',
                 'Несуществующий корень', 'Пустой корень', 'Относительный корень',
                 'Файл вместо корня', 'Символическая ссылка корня',
                 'Символическая ссылка обязательного файла',
                 'Символическая ссылка каталога фикстур', 'Родительский переход в корне']


def требовать(условие, сообщение):
    if not условие:
        raise ValueError(сообщение)


def поля(данные, имена):
    требовать(type(данные) is dict and set(данные) == set(имена), 'Неверный набор полей')


def целое(значение):
    требовать(type(значение) is int and значение >= 0, 'Нужно неотрицательное целое')


def хэш(значение, префикс=''):
    требовать(type(значение) is str and re.fullmatch(re.escape(префикс) + '[0-9a-f]{64}', значение),
              'Неверный SHA256')


def проверить_хэши(данные, корень, имена):
    поля(данные, имена)
    for имя, значение in данные.items():
        хэш(значение)
        путь = Path(имя)
        требовать(not путь.is_absolute() and all(часть not in {'.', '..'} for часть in путь.parts),
                  'Хэш привязан к неверному пути')
        файл = корень / путь
        требовать(not файл.is_symlink() and файл.is_file()
                  and hashlib.sha256(файл.read_bytes()).hexdigest() == значение,
                  'Хэш не соответствует исходным байтам')


def проверить_служебные_пути(кэш, выход, журналы=None):
    пути = [Path(путь).absolute() for путь in [кэш, выход, журналы] if путь is not None]
    for путь in пути:
        требовать(not путь.resolve().is_relative_to(КОРЕНЬ.parents[3]),
                  'Служебные результаты должны находиться вне checkout')
        for часть in [*reversed(путь.parents), путь]:
            требовать(not часть.is_symlink(), 'Символическая ссылка служебного пути запрещена')
            if часть != путь and часть.exists():
                требовать(часть.is_dir(), 'Родитель должен быть каталогом')
    for номер, путь in enumerate(пути):
        for другой in пути[номер + 1:]:
            требовать(not путь.resolve().is_relative_to(другой.resolve())
                      and not другой.resolve().is_relative_to(путь.resolve()),
                      'Служебные пути пересекаются')
    требовать(not Path(кэш).exists() or Path(кэш).is_dir(), 'Кэш должен быть каталогом')
    for путь in [выход, журналы]:
        if путь is not None:
            требовать(not Path(путь).exists() and not Path(путь).is_symlink(),
                      'Результаты и сырые журналы не перезаписываются')


def записать_результат(путь, данные):
    байты = (json.dumps(данные, ensure_ascii=False, indent=2, allow_nan=False) + '\n').encode()
    with Path(путь).open('xb') as поток:
        поток.write(байты)


def проверить_результат(результат, журналы=None):
    поля(результат, ['схема', 'вызовы', 'макрос_пути_исходника', 'другой_рабочий_каталог',
                    'хэши_исходников', 'успех'])
    требовать(результат['схема'] == 'klaviatura.публикационная-привязка.2', 'Неверная схема публикации')
    for имя in ['макрос_пути_исходника', 'другой_рабочий_каталог', 'успех']:
        требовать(type(результат[имя]) is bool, 'Нужно логическое значение')
    требовать(результат['другой_рабочий_каталог'], 'Не подтверждён другой рабочий каталог')
    проверить_хэши(результат['хэши_исходников'], КОРЕНЬ, ИСХОДНИКИ)
    вызовы = результат['вызовы']
    требовать(type(вызовы) is list and len(вызовы) == 10, 'Нужны все десять сценариев')
    for номер, вызов in enumerate(вызовы):
        поля(вызов, ['вызов', 'код', 'длительность_нс', 'соответствие', 'отказ_корня',
                    'хэш_стандартного_вывода', 'хэш_диагностического_вывода'])
        требовать(вызов['вызов'] == ИМЕНА_ВЫЗОВОВ[номер] and type(вызов['код']) is int,
                  'Неверный сценарий или код процесса')
        целое(вызов['длительность_нс'])
        for имя in ['соответствие', 'отказ_корня']:
            требовать(type(вызов[имя]) is bool, 'Нужно логическое значение исхода')
        for имя in ['хэш_стандартного_вывода', 'хэш_диагностического_вывода']:
            хэш(вызов[имя])
        if журналы is not None:
            потоки = []
            for имя, суффикс in [('хэш_стандартного_вывода', 'stdout'),
                                ('хэш_диагностического_вывода', 'stderr')]:
                файл = Path(журналы) / (str(номер) + '-' + суффикс)
                требовать(not файл.is_symlink() and файл.is_file()
                    and hashlib.sha256(файл.read_bytes()).hexdigest() == вызов[имя],
                    'Хэш не соответствует сырому журналу')
                потоки.append(файл.read_bytes())
            требовать(вызов['отказ_корня'] == ('КЛАВИАТУРА:'.encode() in b''.join(потоки)),
                      'Диагностика корня не соответствует сырому журналу')
        ожидаемое = вызов['код'] == 0 if номер == 0 else вызов['код'] != 0 and вызов['отказ_корня']
        требовать(вызов['соответствие'] == ожидаемое, 'Исход сценария противоречит процессу')
    требовать(результат['успех'] == (not результат['макрос_пути_исходника']
              and all(вызов['соответствие'] for вызов in вызовы)), 'Неверный общий исход')


def основная():
    разбор = argparse.ArgumentParser()
    разбор.add_argument('--кэш', type=Path, required=True)
    разбор.add_argument('--выход', type=Path, required=True)
    разбор.add_argument('--журналы', type=Path, required=True)
    параметры = разбор.parse_args()
    проверить_служебные_пути(параметры.кэш, параметры.выход, параметры.журналы)
    журналы = параметры.журналы.resolve()
    журналы.mkdir(parents=True, mode=0o700)
    другой = журналы / 'другой-каталог'
    другой.mkdir()
    ссылка = журналы / 'ссылка-корня'
    ссылка.symlink_to(КОРЕНЬ, target_is_directory=True)
    образцы = []
    for имя in ['ссылка-файла', 'ссылка-каталога']:
        образец = журналы / имя
        образец.mkdir()
        for файл in ['Package.swift', 'определение.json']:
            shutil.copyfile(КОРЕНЬ / файл, образец / файл)
        if имя == 'ссылка-файла':
            (образец / 'Фикстуры').mkdir()
            (образец / 'Фикстуры/переходы.json').symlink_to(КОРЕНЬ / 'Фикстуры/переходы.json')
        else:
            (образец / 'Фикстуры').symlink_to(КОРЕНЬ / 'Фикстуры', target_is_directory=True)
        образцы.append(образец)
    варианты = [
        (ИМЕНА_ВЫЗОВОВ[0], str(КОРЕНЬ), True),
        ('Отсутствующий корень', None, False),
        ('Несуществующий корень', str(другой / 'отсутствует'), False),
        ('Пустой корень', '', False),
        ('Относительный корень', '.', False),
        ('Файл вместо корня', str(КОРЕНЬ / 'Package.swift'), False),
        ('Символическая ссылка корня', str(ссылка), False),
        ('Символическая ссылка обязательного файла', str(образцы[0]), False),
        ('Символическая ссылка каталога фикстур', str(образцы[1]), False),
        ('Родительский переход в корне', str(КОРЕНЬ) + '/../Klaviatura', False),
    ]
    вызовы = []
    for номер, (имя, значение, успех) in enumerate(варианты):
        среда = dict(os.environ)
        среда.pop('KLAVIATURA_RED', None)
        среда.pop(ПЕРЕМЕННАЯ_КОРНЯ, None)
        if значение is not None:
            среда[ПЕРЕМЕННАЯ_КОРНЯ] = значение
        команда = ['swift', 'test', '--package-path', str(КОРЕНЬ), '--scratch-path', str(параметры.кэш.resolve()), '-j', '2']
        if номер:
            команда += ['--skip-build', '--filter', 'testПервыйТекстНастоящимИнтерпретатором']
        начало = time.perf_counter_ns()
        процесс = subprocess.run(команда, cwd=другой, env=среда, capture_output=True)
        длительность = time.perf_counter_ns() - начало
        (журналы / (str(номер) + '-stdout')).write_bytes(процесс.stdout)
        (журналы / (str(номер) + '-stderr')).write_bytes(процесс.stderr)
        объяснение = 'КЛАВИАТУРА:'.encode() in процесс.stdout + процесс.stderr
        соответствует = процесс.returncode == 0 if успех else процесс.returncode != 0 and объяснение
        вызовы.append({'вызов': имя, 'код': процесс.returncode, 'длительность_нс': длительность,
                       'соответствие': соответствует, 'отказ_корня': объяснение,
                       'хэш_стандартного_вывода': hashlib.sha256(процесс.stdout).hexdigest(),
                       'хэш_диагностического_вывода': hashlib.sha256(процесс.stderr).hexdigest()})
    исходник = (КОРЕНЬ / 'Tests/ПроверкиКлавиатуры/ПроверкиПереходов.swift').read_bytes()
    макрос = re.search(rb'#[f]ile(?:Path|ID)?\b', исходник) is not None
    результат = {'схема': 'klaviatura.публикационная-привязка.2', 'вызовы': вызовы,
                 'макрос_пути_исходника': макрос, 'другой_рабочий_каталог': True,
                 'хэши_исходников': {имя: hashlib.sha256((КОРЕНЬ / имя).read_bytes()).hexdigest() for имя in ИСХОДНИКИ},
                 'успех': not макрос and all(вызов['соответствие'] for вызов in вызовы)}
    проверить_результат(результат, журналы)
    записать_результат(параметры.выход, результат)
    print(json.dumps({'успех': результат['успех'], 'вызовов': len(вызовы)}, ensure_ascii=False))
    return 0 if результат['успех'] else 1


if __name__ == '__main__':
    raise SystemExit(основная())

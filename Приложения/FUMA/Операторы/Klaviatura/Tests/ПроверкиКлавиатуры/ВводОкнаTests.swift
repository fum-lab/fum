import Foundation
import XCTest
import FUMStructuringOperatorMemory
import ЭталонКлавиатуры

final class ВводОкнаTests: XCTestCase {
  private var корень: URL!
  private var окно: ИдентификаторОкнаВвода!
  private var фокусА: ИдентификаторФокусаВвода!
  private var фокусБ: ИдентификаторФокусаВвода!

  override func setUpWithError() throws {
    guard let значение = ProcessInfo.processInfo.environment["КЛАВИАТУРА_КОРЕНЬ_ПАКЕТА"],
          значение.hasPrefix("/") else {
      throw NSError(domain: "Klaviatura.ввод-окна", code: 1,
                    userInfo: [NSLocalizedDescriptionKey: "КЛАВИАТУРА: отсутствует физический корень пакета"])
    }
    корень = URL(fileURLWithPath: значение, isDirectory: true)
    окно = ИдентификаторОкнаВвода(rawValue: UUID())
    фокусА = ИдентификаторФокусаВвода(rawValue: UUID())
    фокусБ = ИдентификаторФокусаВвода(rawValue: UUID())
  }

  private func новыйАдаптер() throws -> АдаптерВводаОкна {
    let байтыОпределения = try Data(contentsOf: корень.appendingPathComponent("определение.json"))
    let байтыТаблицы = try Data(contentsOf: корень.appendingPathComponent("таблица-раскладки.json"))
    return try АдаптерВводаОкна(
      окно: окно,
      байтыОпределения: байтыОпределения,
      байтыТаблицы: байтыТаблицы,
      привязка: .keyboardQwertyV1
    )
  }

  func testЗакреплённыеБайтыГрафаИТаблицыИсполняютБазовыйСлой() throws {
    var адаптер = try новыйАдаптер()
    let результат = try адаптер.принять(
      .init(код: 12, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: окно,
      фокус: фокусА
    )

    XCTAssertEqual(результат.раскладка, .qwerty)
    XCTAssertEqual(результат.вывод, .текст("q", источник: .fuma))
    XCTAssertEqual(результат.состояние, .пустое)
    XCTAssertEqual(результат.трасса?.шаги.map(\.идентификатор), ["переход-раскладки"])
    XCTAssertEqual(результат.трасса?.хэшОпределения, АдаптерВводаОкна.привязкаQwertyV1.хэшОпределения)
  }

  func testСостояниеСдвигаИОпцииВозвращаетсяГрафомИПереиспользуется() throws {
    var адаптер = try новыйАдаптер()
    let сдвигНажат = try адаптер.принять(
      .init(код: 56, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    XCTAssertEqual(сдвигНажат.вывод, .нет)
    XCTAssertTrue(сдвигНажат.состояние.сдвигСлева)

    let сдвинутыйСимвол = try адаптер.принять(
      .init(код: 12, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    XCTAssertEqual(сдвинутыйСимвол.вывод, .текст("Q", источник: .fuma))

    _ = try адаптер.принять(
      .init(код: 56, фаза: .отпускание, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    _ = try адаптер.принять(
      .init(код: 58, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    let опционныйСимвол = try адаптер.принять(
      .init(код: 12, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    XCTAssertEqual(опционныйСимвол.вывод, .текст("*", источник: .fuma))
    XCTAssertTrue(опционныйСимвол.состояние.опцияСлева)
  }

  func testПовторУдалениеИОтпусканиеВозвращаютКонтрактГрафа() throws {
    var адаптер = try новыйАдаптер()
    let повтор = try адаптер.принять(
      .init(код: 12, фаза: .нажатие, повтор: true, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    XCTAssertEqual(повтор.вывод, .нет)
    XCTAssertNotNil(повтор.трасса)

    let delete = try адаптер.принять(
      .init(код: 51, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    XCTAssertEqual(delete.вывод, .команда("удалить-назад"))

    let отпускание = try адаптер.принять(
      .init(код: 51, фаза: .отпускание, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    XCTAssertEqual(отпускание.вывод, .нет)
  }

  func testIMECommitОтделёнОтФизическогоСобытияИНеДублируется() throws {
    var адаптер = try новыйАдаптер()
    let идентификаторКомпозиции = UUID()
    let воВремяКомпозиции = try адаптер.принять(
      .init(код: 12, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      композицияIME: .составляется(идентификаторКомпозиции),
      вОкне: окно, фокус: фокусА
    )
    XCTAssertEqual(воВремяКомпозиции.вывод, .нет)
    XCTAssertNotNil(воВремяКомпозиции.трасса)

    let commit = СобытиеIME.зафиксировать(идентификатор: идентификаторКомпозиции, текст: "かな")
    let составленныйТекст = адаптер.принять(commit, вОкне: окно, фокус: фокусА)
    XCTAssertEqual(составленныйТекст.вывод, .текст("かな", источник: .ime))
    XCTAssertNil(составленныйТекст.трасса)

    let повторCommit = адаптер.принять(commit, вОкне: окно, фокус: фокусА)
    XCTAssertEqual(повторCommit.вывод, .нет)
    XCTAssertNil(повторCommit.трасса)
  }

  func testСменаФокусаСбрасываетСостояниеГрафа() throws {
    var адаптер = try новыйАдаптер()
    _ = try адаптер.принять(
      .init(код: 56, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусА
    )
    let новыйФокус = try адаптер.принять(
      .init(код: 12, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: окно, фокус: фокусБ
    )
    XCTAssertEqual(новыйФокус.вывод, .текст("q", источник: .fuma))
    XCTAssertFalse(новыйФокус.состояние.сдвигСлева)
  }

  func testЧужоеОкноИНеизвестнаяРаскладкаНеВызываютГрафИНеИмеютFallback() throws {
    var адаптер = try новыйАдаптер()
    let чужоеОкно = ИдентификаторОкнаВвода(rawValue: UUID())
    let чужойВвод = try адаптер.принять(
      .init(код: 12, фаза: .нажатие, повтор: false, раскладка: .qwerty),
      вОкне: чужоеОкно, фокус: фокусА
    )
    XCTAssertEqual(чужойВвод.вывод, .нет)
    XCTAssertNil(чужойВвод.трасса)

    let неизвестнаяРаскладка = try адаптер.принять(
      .init(код: 12, фаза: .нажатие, повтор: false, раскладка: .dvorak),
      вОкне: окно, фокус: фокусА
    )
    XCTAssertEqual(неизвестнаяРаскладка.раскладка, .dvorak)
    XCTAssertEqual(неизвестнаяРаскладка.статус, .раскладкаНеПроверена)
    XCTAssertEqual(неизвестнаяРаскладка.вывод, .нет)
    XCTAssertNil(неизвестнаяРаскладка.трасса)
  }

  func testНесовпавшиеЗакреплённыеБайтыОтвергаютсяДоИсполнения() throws {
    let байтыОпределения = try Data(contentsOf: корень.appendingPathComponent("определение.json"))
    let байтыТаблицы = try Data(contentsOf: корень.appendingPathComponent("таблица-раскладки.json"))
    XCTAssertThrowsError(try АдаптерВводаОкна(
      окно: окно,
      байтыОпределения: байтыОпределения + Data([0]),
      байтыТаблицы: байтыТаблицы,
      привязка: .keyboardQwertyV1
    ))
    XCTAssertThrowsError(try АдаптерВводаОкна(
      окно: окно,
      байтыОпределения: байтыОпределения,
      байтыТаблицы: байтыТаблицы + Data([0]),
      привязка: .keyboardQwertyV1
    ))
  }
}

  /// Processes one eligible physical event through the pinned FUMA graph.
  public mutating func принять(
    _ событие: ФизическоеСобытиеКлавиатуры
  ) throws -> РезультатВводаКлавиатурыОкна {
    guard событие.свидетельство.окно == окно else {
      return результат(.проигнорировано, .пропустить, событие.раскладка, событие.свидетельство)
    }
    if физическиеСобытия[событие.идентификатор] == nil,
       событияIME[событие.идентификатор] != nil {
      инвалидироватьСостояние()
      return результат(.неизвестно, .неизвестен, событие.раскладка, событие.свидетельство)
    }
    if let прежнее = физическиеСобытия[событие.идентификатор] {
      if прежнее == событие {
        return результат(.повторСобытия, .потребить, событие.раскладка, событие.свидетельство)
      }
      инвалидироватьСостояние()
      return результат(.неизвестно, .неизвестен, событие.раскладка, событие.свидетельство)
    }
    guard фокус == событие.свидетельство.фокус,
          поколениеФокуса == событие.свидетельство.поколениеФокуса else {
      return результат(.неизвестно, .неизвестен, событие.раскладка, событие.свидетельство)
    }
    guard принятьПорядок(событие.свидетельство) else {
      инвалидироватьСостояние()
      return результат(.неизвестно, .неизвестен, событие.раскладка, событие.свидетельство)
    }
    физическиеСобытия[событие.идентификатор] = событие
    последнееФизическоеСобытие = событие.идентификатор
    ограничитьИсторию()

    if let снимок = событие.снимокМодификаторов {
      состояниеМодификаторов = снимок
      состояниеДействительно = true
    }
    guard состояниеДействительно else {
      активнаяКомпозиция = nil
      return результат(.неизвестно, .неизвестен, событие.раскладка, событие.свидетельство)
    }
    guard событие.раскладка == привязка.идентификаторРаскладки else {
      инвалидироватьСостояние()
      return результат(.раскладкаНеПроверена, .неизвестен, событие.раскладка, событие.свидетельство)
    }

    let активнаяIME: Bool
    switch событие.обработкаНативнымКраем {
    case .fuma:
      if активнаяКомпозиция != nil {
        активнаяIME = true
      } else {
        активнаяIME = false
      }
    case .системноеСочетание:
      активнаяIME = false
    case .ime(let идентификаторКомпозиции):
      guard let идентификаторКомпозиции else {
        let неизвестныйИсход = try исполнить(событие, сВыводом: .неизвестно)
        инвалидироватьСостояние()
        return неизвестныйИсход
      }
      if let активнаяКомпозиция,
         (активнаяКомпозиция.идентификатор != идентификаторКомпозиции || активнаяКомпозиция.фокус != фокус!) {
        инвалидироватьСостояние()
        return результат(.неизвестно, .неизвестен, событие.раскладка, событие.свидетельство)
      }
      активнаяКомпозиция = АктивнаяКомпозиция(идентификатор: идентификаторКомпозиции, фокус: фокус!)
      активнаяIME = true
    case .порядокНеизвестен:
      let неизвестныйИсход = try исполнить(событие, сВыводом: .неизвестно)
      инвалидироватьСостояние()
      return неизвестныйИсход
    }
    return try исполнить(
      событие,
      сВыводом: активнаяIME ? .ime : (событие.обработкаНативнымКраем == .системноеСочетание ? .системноеСочетание : .fuma)
    )
  }

  /// A valid IME callback must follow and correlate with the latest physical event in this focus generation.
  public mutating func принять(_ событие: СобытиеIME) -> РезультатВводаКлавиатурыОкна {
    guard событие.свидетельство.окно == окно else {
      return результат(.проигнорировано, .пропустить, nil, событие.свидетельство)
    }
    if let прежнее = событияIME[событие.идентификатор] {
      if прежнее == событие {
        return результат(.повторСобытия, .подавитьПовтор, nil, событие.свидетельство)
      }
      инвалидироватьСостояние()
      return результат(.неизвестно, .неизвестен, nil, событие.свидетельство)
    }
    if физическиеСобытия[событие.идентификатор] != nil {
      инвалидироватьСостояние()
      return результат(.неизвестно, .неизвестен, nil, событие.свидетельство)
    }
    guard фокус == событие.свидетельство.фокус,
          поколениеФокуса == событие.свидетельство.поколениеФокуса,
          let связаноСФизическимСобытием = событие.связаноСФизическимСобытием,
          связаноСФизическимСобытием == последнееФизическоеСобытие else {
      инвалидироватьСостояние()
      return результат(.неизвестно, .неизвестен, nil, событие.свидетельство)
    }
    guard принятьПорядок(событие.свидетельство) else {
      инвалидироватьСостояние()
      return результат(.неизвестно, .неизвестен, nil, событие.свидетельство)
    }
    событияIME[событие.идентификатор] = событие
    ограничитьИсторию()

    switch событие.вид {
    case .начать:
      if let активнаяКомпозиция,
         активнаяКомпозиция != АктивнаяКомпозиция(идентификатор: событие.композиция, фокус: событие.свидетельство.фокус) {
        return результат(.неизвестно, .неизвестен, nil, событие.свидетельство)
      }
      активнаяКомпозиция = АктивнаяКомпозиция(идентификатор: событие.композиция, фокус: событие.свидетельство.фокус)
      return результат(.обработано, .пропустить, nil, событие.свидетельство)
    case .обновить:
      guard композицияСовпадает(событие) else {
        return результат(.неизвестно, .неизвестен, nil, событие.свидетельство)
      }
      return результат(.обработано, .пропустить, nil, событие.свидетельство)
    case .зафиксировать(let текст):
      guard композицияСовпадает(событие) else {
        return результат(.неизвестно, .неизвестен, nil, событие.свидетельство)
      }
      активнаяКомпозиция = nil
      return результат(
        .обработано,
        .пропустить,
        nil,
        событие.свидетельство,
        вывод: текст.isEmpty ? .нет : .составленныйIMEТекст(текст)
      )
    case .отменить:
      guard композицияСовпадает(событие) else {
        return результат(.неизвестно, .неизвестен, nil, событие.свидетельство)
      }
      активнаяКомпозиция = nil
      return результат(.обработано, .пропустить, nil, событие.свидетельство)
    }
  }

  private enum КаналВывода {
    case fuma
    case системноеСочетание
    case ime
    case неизвестно
  }

  private mutating func исполнить(
    _ событие: ФизическоеСобытиеКлавиатуры,
    сВыводом канал: КаналВывода
  ) throws -> РезультатВводаКлавиатурыОкна {
    let вход = ВходПерехода(
      клавиша: событие.код,
      фаза: событие.фаза.rawValue,
      повтор: событие.повтор,
      модификаторы: состояниеМодификаторов
    )
    let наблюдение = try AutomationExecutor.выполнить(
      определение,
      вход: .текст(try Self.кодировать(вход))
    )
    guard наблюдение.хэшОпределения == привязка.хэшКаноническогоОпределения else {
      throw ОшибкаАдаптераВводаОкна.несовпавшийХэшКаноническогоОпределения(
        ожидалось: привязка.хэшКаноническогоОпределения,
        получено: наблюдение.хэшОпределения
      )
    }
    guard case .текст(let текстРезультата) = наблюдение.результат,
          let данныеРезультата = текстРезультата.data(using: .utf8) else {
      throw ОшибкаАдаптераВводаОкна.неверныйФорматГрафа
    }
    let выход = try JSONDecoder().decode(ВыходПерехода.self, from: данныеРезультата)
    guard выход.трасса.оператор == привязка.идентификаторОператора,
          выход.трасса.версия == привязка.версияОператора,
          выход.трасса.клавиша == событие.код,
          выход.трасса.фаза == событие.фаза.rawValue,
          выход.трасса.повтор == событие.повтор else {
      throw ОшибкаАдаптераВводаОкна.неверныйФорматГрафа
    }

    состояниеМодификаторов = выход.модификаторы
    состояниеДействительно = true
    let вывод: ВыводКлавиатурыОкна
    let маршрут: МаршрутСобытияКлавиатуры
    let статус: СтатусВводаКлавиатурыОкна
    switch канал {
    case .ime:
      вывод = .нет
      маршрут = .пропустить
      статус = .обработано
    case .системноеСочетание:
      вывод = .нет
      маршрут = .пропустить
      статус = .обработано
    case .неизвестно:
      вывод = .нет
      маршрут = .неизвестен
      статус = .неизвестно
    case .fuma:
      switch (выход.статус, выход.вывод.вид) {
      case ("поддержано", "текст"):
        вывод = выход.вывод.значение.isEmpty ? .нет : .текст(выход.вывод.значение, источник: .fuma)
        маршрут = .потребить
        статус = .обработано
      case ("поддержано", "команда"):
        вывод = выход.вывод.значение.isEmpty ? .нет : .команда(выход.вывод.значение)
        маршрут = .потребить
        статус = .обработано
      case ("поддержано", "нет"):
        вывод = .нет
        маршрут = .потребить
        статус = .обработано
      case ("неподдержано", _):
        вывод = .нет
        маршрут = .пропустить
        статус = .обработано
      default:
        throw ОшибкаАдаптераВводаОкна.неизвестныйРезультатГрафа
      }
    }
    return результат(статус, маршрут, событие.раскладка, событие.свидетельство, вывод: вывод, трасса: наблюдение)
  }

  private mutating func принятьПорядок(_ свидетельство: СвидетельствоСобытияКлавиатуры) -> Bool {
    let следующийПорядок = последнийПорядок.addingReportingOverflow(1)
    let порядокСовпадает = !следующийПорядок.overflow && свидетельство.порядок == следующийПорядок.partialValue
    let времяНеУменьшается = последнийМоментНаблюденияНс.map {
      свидетельство.моментНаблюденияНс >= $0
    } ?? true
    guard порядокСовпадает, времяНеУменьшается else {
      if свидетельство.порядок > последнийПорядок { последнийПорядок = свидетельство.порядок }
      if последнийМоментНаблюденияНс.map({ свидетельство.моментНаблюденияНс > $0 }) ?? true {
        последнийМоментНаблюденияНс = свидетельство.моментНаблюденияНс
      }
      return false
    }
    последнийПорядок = свидетельство.порядок
    последнийМоментНаблюденияНс = свидетельство.моментНаблюденияНс
    return true
  }

  /// Retain a bounded exact replay window. Older events remain rejected by the sequence high-watermark.
  private mutating func ограничитьИсторию() {
    while физическиеСобытия.count + событияIME.count > Self.максимумИсторииСобытий {
      let физическое = физическиеСобытия.values
        .filter { $0.идентификатор != последнееФизическоеСобытие }
        .min { $0.свидетельство.порядок < $1.свидетельство.порядок }
      let ime = событияIME.values.min { $0.свидетельство.порядок < $1.свидетельство.порядок }

      switch (физическое, ime) {
      case let (.some(физическое), .some(ime)):
        if физическое.свидетельство.порядок <= ime.свидетельство.порядок {
          физическиеСобытия.removeValue(forKey: физическое.идентификатор)
        } else {
          событияIME.removeValue(forKey: ime.идентификатор)
        }
      case let (.some(физическое), .none):
        физическиеСобытия.removeValue(forKey: физическое.идентификатор)
      case let (.none, .some(ime)):
        событияIME.removeValue(forKey: ime.идентификатор)
      case (.none, .none):
        return
      }
    }
  }

  private func композицияСовпадает(_ событие: СобытиеIME) -> Bool {
    guard let активнаяКомпозиция else { return false }
    return активнаяКомпозиция.идентификатор == событие.композиция
      && активнаяКомпозиция.фокус == событие.свидетельство.фокус
  }

  private mutating func инвалидироватьСостояние() {
    состояниеМодификаторов = .пустое
    состояниеДействительно = false
    активнаяКомпозиция = nil
  }

  private func результат(
    _ статус: СтатусВводаКлавиатурыОкна,
    _ маршрут: МаршрутСобытияКлавиатуры,
    _ раскладка: ИдентификаторРаскладкиКлавиатуры?,
    _ свидетельство: СвидетельствоСобытияКлавиатуры?,
    вывод: ВыводКлавиатурыОкна = .нет,
    трасса: НаблюдениеОператора? = nil
  ) -> РезультатВводаКлавиатурыОкна {
    РезультатВводаКлавиатурыОкна(
      статус: статус,
      маршрут: маршрут,
      раскладка: раскладка,
      свидетельство: свидетельство,
      вывод: вывод,
      состояние: состояниеМодификаторов,
      трасса: трасса
    )
  }

  private static func sha256(_ данные: Data) -> String {
    "sha256:" + SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
  }

  private static func sha256Raw(_ данные: Data) -> String {
    String(sha256(данные).dropFirst("sha256:".count))
  }

  private static func кодировать(_ вход: ВходПерехода) throws -> String {
    let кодировщик = JSONEncoder()
    кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
    let данные = try кодировщик.encode(вход)
    guard let строка = String(data: данные, encoding: .utf8) else {
      throw ОшибкаАдаптераВводаОкна.неверныйФорматГрафа
    }
    return строка
  }

/// Stateful adapter for one owned window. All event calls must be serialized by that window owner.
public struct АдаптерВводаОкна {
  private static let максимумИсторииСобытий = 256

  public let окно: ИдентификаторОкнаВвода
  public let привязка: ПривязкаРаскладкиKeyboard

  private struct АктивнаяКомпозиция: Equatable {
    let идентификатор: UUID
    let фокус: ИдентификаторФокусаВвода
  }

  private let определение: ОпределениеОператора
  private var фокус: ИдентификаторФокусаВвода?
  private var поколениеФокуса: UInt64?
  private var максимальноеПоколениеФокуса: UInt64 = 0
  private var последнийИдентификаторФокуса: ИдентификаторФокусаВвода?
  private var моментПодтвержденияФокусаНс: UInt64?
  private var последнийМоментНаблюденияНс: UInt64?
  private var состояниеМодификаторов: СостояниеМодификаторовКлавиатуры = .пустое
  private var состояниеДействительно = false
  private var последнийПорядок: UInt64 = 0
  private var последнееФизическоеСобытие: ИдентификаторСобытияКлавиатуры?
  private var активнаяКомпозиция: АктивнаяКомпозиция?
  private var физическиеСобытия: [ИдентификаторСобытияКлавиатуры: ФизическоеСобытиеКлавиатуры] = [:]
  private var событияIME: [ИдентификаторСобытияКлавиатуры: СобытиеIME] = [:]

  public init(
    окно: ИдентификаторОкнаВвода,
    байтыОпределения: Data,
    байтыТаблицы: Data,
    привязка: ПривязкаРаскладкиKeyboard,
    восстанавливая снимок: СнимокСобытийКлавиатуры? = nil
  ) throws {
    let хэшОпределения = Self.sha256Raw(байтыОпределения)
    guard хэшОпределения == привязка.хэшОпределения else {
      throw ОшибкаАдаптераВводаОкна.несовпавшийХэшОпределения(
        ожидалось: привязка.хэшОпределения,
        получено: хэшОпределения
      )
    }
    let хэшТаблицы = Self.sha256Raw(байтыТаблицы)
    guard хэшТаблицы == привязка.хэшТаблицы else {
      throw ОшибкаАдаптераВводаОкна.несовпавшийХэшТаблицы(
        ожидалось: привязка.хэшТаблицы,
        получено: хэшТаблицы
      )
    }

    let определение = try ОпределениеОператора.разобрать(байтыОпределения)
    guard определение.идентификатор == привязка.идентификаторОператора,
          определение.версия == привязка.версияОператора else {
      throw ОшибкаАдаптераВводаОкна.несовпавшееОпределениеОператора
    }
    let хэшКаноническогоОпределения = Self.sha256(try определение.данные())
    guard хэшКаноническогоОпределения == привязка.хэшКаноническогоОпределения else {
      throw ОшибкаАдаптераВводаОкна.несовпавшийХэшКаноническогоОпределения(
        ожидалось: привязка.хэшКаноническогоОпределения,
        получено: хэшКаноническогоОпределения
      )
    }
    let таблица = try JSONDecoder().decode(ЗаголовокТаблицы.self, from: байтыТаблицы)
    guard таблица.схема == привязка.схемаТаблицы,
          таблица.раскладка == привязка.идентификаторРаскладки.rawValue else {
      throw ОшибкаАдаптераВводаОкна.несовпавшаяТаблица
    }

    self.окно = окно
    self.привязка = привязка
    self.определение = определение
    if let снимок {
      guard снимок.окно == окно,
            снимок.хэшОпределения == привязка.хэшОпределения,
            снимок.хэшТаблицы == привязка.хэшТаблицы,
            (снимок.фокус == nil) == (снимок.поколениеФокуса == nil),
            снимок.фокус == nil || снимок.фокус == снимок.последнийИдентификаторФокуса,
            снимок.поколениеФокуса == nil || снимок.поколениеФокуса == снимок.максимальноеПоколениеФокуса,
            (снимок.максимальноеПоколениеФокуса == 0) == (снимок.последнийИдентификаторФокуса == nil),
            снимок.поколениеФокуса == nil || снимок.поколениеФокуса! > 0,
            (снимок.композиция == nil) == (снимок.фокусКомпозиции == nil),
            снимок.фокусКомпозиции == nil || снимок.фокусКомпозиции == снимок.фокус,
            снимок.последнееФизическоеСобытие == nil
              || снимок.физическиеСобытия.contains(where: { $0.идентификатор == снимок.последнееФизическоеСобытие }),
            снимок.физическиеСобытия.count + снимок.событияIME.count <= Self.максимумИсторииСобытий,
            !снимок.состояниеДействительно || снимок.фокус != nil,
            (снимок.фокус == nil) == (снимок.моментПодтвержденияФокусаНс == nil),
            (снимок.фокус == nil) == (снимок.последнийМоментНаблюденияНс == nil),
            снимок.фокус != nil || (снимок.последнийПорядок == 0
              && снимок.последнееФизическоеСобытие == nil
              && снимок.физическиеСобытия.isEmpty && снимок.событияIME.isEmpty),
            снимок.моментПодтвержденияФокусаНс == nil
              || снимок.последнийМоментНаблюденияНс! >= снимок.моментПодтвержденияФокусаНс!,
            снимок.физическиеСобытия.allSatisfy({
              $0.свидетельство.окно == окно && $0.свидетельство.фокус == снимок.фокус
                && $0.свидетельство.поколениеФокуса == снимок.поколениеФокуса
                && $0.свидетельство.порядок <= снимок.последнийПорядок
            }),
            снимок.событияIME.allSatisfy({
              $0.свидетельство.окно == окно && $0.свидетельство.фокус == снимок.фокус
                && $0.свидетельство.поколениеФокуса == снимок.поколениеФокуса
                && $0.свидетельство.порядок <= снимок.последнийПорядок
            }) else {
        throw ОшибкаАдаптераВводаОкна.несовпавшийСнимок
      }
      var физические: [ИдентификаторСобытияКлавиатуры: ФизическоеСобытиеКлавиатуры] = [:]
      for событие in снимок.физическиеСобытия {
        guard физические.updateValue(событие, forKey: событие.идентификатор) == nil else {
          throw ОшибкаАдаптераВводаОкна.несовпавшийСнимок
        }
      }
      var ime: [ИдентификаторСобытияКлавиатуры: СобытиеIME] = [:]
      for событие in снимок.событияIME {
        guard ime.updateValue(событие, forKey: событие.идентификатор) == nil else {
          throw ОшибкаАдаптераВводаОкна.несовпавшийСнимок
        }
      }
      guard Set(физические.keys).isDisjoint(with: Set(ime.keys)) else {
        throw ОшибкаАдаптераВводаОкна.несовпавшийСнимок
      }
      self.фокус = снимок.фокус
      self.поколениеФокуса = снимок.поколениеФокуса
      self.максимальноеПоколениеФокуса = снимок.максимальноеПоколениеФокуса
      self.последнийИдентификаторФокуса = снимок.последнийИдентификаторФокуса
      self.моментПодтвержденияФокусаНс = снимок.моментПодтвержденияФокусаНс
      self.последнийМоментНаблюденияНс = снимок.последнийМоментНаблюденияНс
      self.состояниеМодификаторов = снимок.состояниеМодификаторов
      self.состояниеДействительно = снимок.состояниеДействительно
      self.последнийПорядок = снимок.последнийПорядок
      self.последнееФизическоеСобытие = снимок.последнееФизическоеСобытие
      if let композиция = снимок.композиция, let фокусКомпозиции = снимок.фокусКомпозиции {
        self.активнаяКомпозиция = АктивнаяКомпозиция(идентификатор: композиция, фокус: фокусКомпозиции)
      }
      self.физическиеСобытия = физические
      self.событияIME = ime
    }
  }


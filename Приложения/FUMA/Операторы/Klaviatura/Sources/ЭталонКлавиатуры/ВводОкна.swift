  /// Starts a generation using the owner's durable monotonic counter and a full modifier snapshot.
  /// A new adapter without a snapshot requires a fresh window identity or an externally retained counter.
  public mutating func подтвердитьФокус(
    вОкне окноСобытия: ИдентификаторОкнаВвода,
    фокус новыйФокус: ИдентификаторФокусаВвода,
    поколение новоеПоколение: UInt64,
    снимокМодификаторов: СостояниеМодификаторовКлавиатуры,
    моментНаблюденияНс: UInt64
  ) -> Bool {
    guard окноСобытия == окно else { return false }
    if фокус == новыйФокус, поколениеФокуса == новоеПоколение {
      guard последнийМоментНаблюденияНс.map({ моментНаблюденияНс >= $0 }) ?? true else {
        return false
      }
      состояниеМодификаторов = снимокМодификаторов
      состояниеДействительно = true
      последнийМоментНаблюденияНс = моментНаблюденияНс
      return true
    }
    guard новоеПоколение > максимальноеПоколениеФокуса else { return false }
    фокус = новыйФокус
    поколениеФокуса = новоеПоколение
    максимальноеПоколениеФокуса = новоеПоколение
    последнийИдентификаторФокуса = новыйФокус
    моментПодтвержденияФокусаНс = моментНаблюденияНс
    последнийМоментНаблюденияНс = моментНаблюденияНс
    состояниеМодификаторов = снимокМодификаторов
    состояниеДействительно = true
    последнийПорядок = 0
    последнееФизическоеСобытие = nil
    активнаяКомпозиция = nil
    физическиеСобытия.removeAll(keepingCapacity: true)
    событияIME.removeAll(keepingCapacity: true)
    return true
  }


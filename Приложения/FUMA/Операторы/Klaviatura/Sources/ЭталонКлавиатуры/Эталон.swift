import Foundation
import FUMStructuringOperatorMemory

public func выполнитьПереход(_ определение: ОпределениеОператора, _ вход: Data) throws -> НаблюдениеОператора {
  guard let текст = String(data: вход, encoding: .utf8) else { throw CocoaError(.fileReadInapplicableStringEncoding) }
  return try AutomationExecutor.выполнить(определение, вход: .текст(текст))
}
public func разобратьРезультат(_ наблюдение: НаблюдениеОператора) throws -> NSDictionary {
  guard case .текст(let текст) = наблюдение.результат else { throw CocoaError(.coderInvalidValue) }
  guard let объект = try JSONSerialization.jsonObject(with: Data(текст.utf8), options: [.fragmentsAllowed]) as? NSDictionary else { throw CocoaError(.coderInvalidValue) }
  return объект
}

public struct СобытиеКлавиатуры: Decodable {
  public let клавиша: Int
  public let фаза: String
  public let повтор: Bool
  public let модификаторы: [String: Bool]
}

public let поляСостояния = ["сдвиг_слева", "сдвиг_справа", "опция_слева", "опция_справа", "команда_слева", "команда_справа", "смешанная_последовательность"]

public func проверитьВход(_ событие: СобытиеКлавиатуры) throws {
  guard Set(событие.модификаторы.keys) == Set(поляСостояния) else { throw CocoaError(.coderInvalidValue) }
}

/// Независимый прямой Swift-эталон; не читает таблицу, определение или ожидания фикстур.
public func эталонныйПереход(_ событие: СобытиеКлавиатуры) throws -> NSDictionary {
  try проверитьВход(событие)
  let коды = [12,13,14,15,17,16,32,34,31,35,0,1,2,3,5,4,38,40,37,41,6,7,8,9,11,45,46,43,47,44,49]
  let буквы = ["q","w","e","r","t","y","u","i","o","p","a","s","d","f","g","h","j","k","l","?","z","x","c","v","b","n","m",",",".","‐"," "]
  let сдвинутые = ["Q","W","E","R","T","Y","U","I","O","P","A","S","D","F","G","H","J","K","L","!","Z","X","C","V","B","N","M",";",":","_"," "]
  let варианты = ["*","'","&","|","~","÷","7","8","9","−","@","#","$","%","^","×","4","5","6","+","{","[","(","<","/","0","1","2","3","="," "]
  let стороны = [56:"сдвиг_слева",60:"сдвиг_справа",58:"опция_слева",61:"опция_справа",55:"команда_слева",54:"команда_справа"]
  var состояние = событие.модификаторы
  var исход = "текст", вид = "нет", значение = "", слой = "нет", статус = "поддержано"
  if !коды.contains(событие.клавиша) && событие.клавиша != 51 && стороны[событие.клавиша] == nil {
    исход = "неизвестная-клавиша"
  } else if !["нажатие", "отпускание", "прикосновение"].contains(событие.фаза) {
    исход = "недопустимая-фаза"
  } else if событие.фаза == "прикосновение" {
    исход = "прикосновение"
  } else if let сторона = стороны[событие.клавиша] {
    if событие.повтор { исход = "повтор-подавлен" }
    else {
      состояние[сторона] = событие.фаза == "нажатие"
      let сдвиг = состояние["сдвиг_слева"]! || состояние["сдвиг_справа"]!
      let опция = состояние["опция_слева"]! || состояние["опция_справа"]!
      состояние["смешанная_последовательность"] = (сдвиг || опция) && (состояние["смешанная_последовательность"]! || (сдвиг && опция))
      исход = событие.фаза == "нажатие" ? "модификатор" : "отпускание"
    }
  } else if событие.фаза == "отпускание" {
    исход = "отпускание"
  } else if состояние["команда_слева"]! || состояние["команда_справа"]! {
    исход = "командное-сочетание"
  } else {
    let сдвиг = состояние["сдвиг_слева"]! || состояние["сдвиг_справа"]!
    let опция = состояние["опция_слева"]! || состояние["опция_справа"]!
    if состояние["смешанная_последовательность"]! || (сдвиг && опция) {
      исход = "смешанные-модификаторы"
    } else if событие.клавиша == 51 {
      исход = "команда"; вид = "команда"; значение = "удалить-назад"
    } else if событие.повтор {
      исход = "повтор-подавлен"
    } else {
      let номер = коды.firstIndex(of: событие.клавиша)!
      вид = "текст"
      слой = сдвиг ? "сдвиг" : (опция ? "опция" : "базовый")
      значение = сдвиг ? сдвинутые[номер] : (опция ? варианты[номер] : буквы[номер])
    }
  }
  if ["неизвестная-клавиша", "недопустимая-фаза", "командное-сочетание", "смешанные-модификаторы"].contains(исход) {
    статус = "неподдержано"; слой = "неподдержано"
  }
  return ["статус": статус, "вывод": ["вид": вид, "значение": значение], "модификаторы": состояние,
    "трасса": ["оператор": "переход-раскладки-Klaviatura", "версия": 1, "клавиша": событие.клавиша, "фаза": событие.фаза, "повтор": событие.повтор, "слой": слой, "исход": исход]]
}

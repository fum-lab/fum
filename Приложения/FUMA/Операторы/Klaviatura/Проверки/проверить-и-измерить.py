КОРЕНЬ = Path(__file__).resolve().parents[1]
ОПИСАНИЕ = importlib.util.spec_from_file_location('публикационная_привязка',
    КОРЕНЬ / 'Сценарии/проверить-публикационную-привязку.py')
КОНТРАКТ = importlib.util.module_from_spec(ОПИСАНИЕ)
ОПИСАНИЕ.loader.exec_module(КОНТРАКТ)
ИСХОДНИКИ = ['Package.swift', 'определение.json', 'таблица-раскладки.json',
    'Фикстуры/переходы.json', 'Фикстуры/последовательность-профиля.json',
    'Сценарии/собрать-определение.py', 'Сценарии/проверить-публикационную-привязку.py',
    'Сценарии/test_контрактов_проверок.py', 'Sources/ЭталонКлавиатуры/Эталон.swift',
    'Sources/ИсполнительКлавиатуры/main.swift', 'Tests/ПроверкиКлавиатуры/ПроверкиПереходов.swift',
    'Проверки/проверить-и-измерить.py']
МЕТРИКИ = ['разбор_входов_нс', 'разбор_определения_нс', 'переходы_нс', 'пик_памяти_байты']


def уникальные_поля(пары):
    результат = {}
    for имя, значение in пары:
        КОНТРАКТ.требовать(имя not in результат, 'Повторное поле JSON')
        результат[имя] = значение
    return результат


def прочитать_объект(путь):
    return json.loads(Path(путь).read_bytes(), object_pairs_hook=уникальные_поля)


def равны(первое, второе):
    return json.dumps(первое, ensure_ascii=False, sort_keys=True, allow_nan=False) == \
           json.dumps(второе, ensure_ascii=False, sort_keys=True, allow_nan=False)


def проверить_прогон(результат, режим, входы):
    имена = ['схема', 'режим', 'число_входов', 'повторы', 'входы', 'выходы', 'профиль']
    КОНТРАКТ.поля(результат, имена + (['наблюдения'] if режим == 'FUMA' else []))
    КОНТРАКТ.требовать(результат['схема'] == 'klaviatura.прогон.1'
        and результат['режим'] == режим and режим in {'FUMA', 'эталон'}, 'Неверный контракт исполнителя')
    КОНТРАКТ.требовать(type(входы) is list and len(входы) > 0
        and type(результат['число_входов']) is int and результат['число_входов'] == len(входы)
        and type(результат['повторы']) is int and результат['повторы'] == 1
        and равны(результат['входы'], входы), 'Неполный или подменённый корпус')
    КОНТРАКТ.поля(результат['профиль'], МЕТРИКИ)
    for значение in результат['профиль'].values(): КОНТРАКТ.целое(значение)
    выходы = результат['выходы']
    КОНТРАКТ.требовать(type(выходы) is list and len(выходы) == len(входы), 'Неполный массив выходов')
    for выход in выходы:
        КОНТРАКТ.поля(выход, ['статус', 'вывод', 'модификаторы', 'трасса'])
    if режим == 'FUMA':
        наблюдения = результат['наблюдения']
        КОНТРАКТ.требовать(type(наблюдения) is list and len(наблюдения) == len(входы), 'Неполные наблюдения')
        # Определение .1 хэшируется runtime после канонического кодирования, без отступов и LF.
        определение = 'sha256:' + hashlib.sha256(json.dumps(
            прочитать_объект(КОРЕНЬ / 'определение.json'), ensure_ascii=False,
            sort_keys=True, separators=(',', ':'), allow_nan=False).encode()).hexdigest()
        for номер, наблюдение in enumerate(наблюдения):
            КОНТРАКТ.поля(наблюдение, ['версияОпределения', 'выполненоОпераций', 'пропущеноЗаписей',
                'результат', 'схема', 'типВхода', 'трасса', 'хэшИсходныхБайтов', 'хэшНаблюдения',
                'хэшОпределения', 'шаги'])
            КОНТРАКТ.требовать(наблюдение['схема'] == 'fum.наблюдение-оператора.1'
                and type(наблюдение['версияОпределения']) is int and наблюдение['версияОпределения'] == 1
                and наблюдение['типВхода'] == 'текст' and наблюдение['трасса'] == [], 'Неверное наблюдение')
            for имя in ['выполненоОпераций', 'пропущеноЗаписей']: КОНТРАКТ.целое(наблюдение[имя])
            КОНТРАКТ.требовать(наблюдение['выполненоОпераций'] > 0
                and наблюдение['пропущеноЗаписей'] == 0, 'Наблюдение не полно')
            for имя in ['хэшИсходныхБайтов', 'хэшНаблюдения', 'хэшОпределения']:
                КОНТРАКТ.хэш(наблюдение[имя], 'sha256:')
            КОНТРАКТ.требовать(наблюдение['хэшОпределения'] == определение, 'Подменено определение')
            КОНТРАКТ.поля(наблюдение['результат'], ['тип', 'значение'])
            КОНТРАКТ.требовать(наблюдение['результат']['тип'] == 'текст'
                and type(наблюдение['результат']['значение']) is str, 'Неверный тип результата')
            КОНТРАКТ.требовать(равны(json.loads(наблюдение['результат']['значение'],
                object_pairs_hook=уникальные_поля), выходы[номер]), 'Подменён результат наблюдения')
            КОНТРАКТ.требовать(type(наблюдение['шаги']) is list and len(наблюдение['шаги']) == 1,
                'Неверный состав шагов')
            шаг = наблюдение['шаги'][0]
            КОНТРАКТ.поля(шаг, ['идентификатор', 'хэшВхода', 'хэшВыхода'])
            КОНТРАКТ.требовать(шаг['идентификатор'] == 'переход-раскладки'
                and шаг['хэшВхода'] == наблюдение['хэшИсходныхБайтов'], 'Подменён шаг')
            КОНТРАКТ.хэш(шаг['хэшВыхода'], 'sha256:')


def проверить_профиль(результат):
    КОНТРАКТ.поля(результат, ['схема', 'статус', 'условия', 'хэши_исходников', 'хэши_интерпретатора',
        'тесты_нс', 'сборка_выпуска_нс', 'пары', 'полный_вход', 'полный_выход',
        'нативные_наблюдения', 'совпадение', 'оптимизация', 'хэш_бинарника'])
    КОНТРАКТ.требовать(результат['схема'] == 'klaviatura.профиль.2'
        and результат['статус'] == 'измерен' and результат['совпадение'] is True, 'Неверный профиль')
    КОНТРАКТ.поля(результат['условия'], ['система', 'архитектура', 'версия_компилятора',
        'процессов_сборки', 'пар', 'прогрев', 'память'])
    for имя in ['система', 'архитектура', 'версия_компилятора', 'прогрев', 'память']:
        КОНТРАКТ.требовать(type(результат['условия'][имя]) is str and результат['условия'][имя],
            'Неизвестные условия профиля')
    for имя, число in [('процессов_сборки', 2), ('пар', 3)]:
        КОНТРАКТ.требовать(type(результат['условия'][имя]) is int
            and результат['условия'][имя] == число, 'Неверные условия профиля')
    КОНТРАКТ.проверить_хэши(результат['хэши_исходников'], КОРЕНЬ, ИСХОДНИКИ)
    библиотека = КОРЕНЬ.parents[3] / 'Прототипы/память-структурирующих-операторов'
    имена = исходники_интерпретатора(библиотека)
    КОНТРАКТ.проверить_хэши(результат['хэши_интерпретатора'], библиотека, имена)
    КОНТРАКТ.хэш(результат['хэш_бинарника'])
    for имя in ['тесты_нс', 'сборка_выпуска_нс']: КОНТРАКТ.целое(результат[имя])
    пары = результат['пары']
    КОНТРАКТ.требовать(type(пары) is list and len(пары) == 3, 'Нужны три пары')
    for пара in пары:
        КОНТРАКТ.поля(пара, ['эталон', 'интерпретатор'])
        for измерение in пара.values():
            КОНТРАКТ.поля(измерение, [*МЕТРИКИ, 'полный_процесс_нс'])
            for значение in измерение.values(): КОНТРАКТ.целое(значение)
    КОНТРАКТ.поля(результат['оптимизация'], ['статус', 'основание'])
    for значение in результат['оптимизация'].values():
        КОНТРАКТ.требовать(type(значение) is str and значение, 'Неизвестное решение об оптимизации')
    входы = прочитать_объект(КОРЕНЬ / 'Фикстуры/последовательность-профиля.json')['входы']
    проверить_прогон({'схема': 'klaviatura.прогон.1', 'режим': 'FUMA', 'число_входов': len(входы),
        'повторы': 1, 'входы': результат['полный_вход'], 'выходы': результат['полный_выход'],
        'наблюдения': результат['нативные_наблюдения'],
        'профиль': {имя: пары[-1]['интерпретатор'][имя] for имя in МЕТРИКИ}}, 'FUMA', входы)


def исходники_интерпретатора(библиотека):
    return [файл.relative_to(библиотека).as_posix() for файл in sorted(библиотека.rglob('*'))
        if файл.is_file() and файл.suffix in {'.swift', '.json'}
        and not any(часть.startswith('.') for часть in файл.relative_to(библиотека).parts)]


def проверенныйКорень():
    for каталог in [КОРЕНЬ, КОРЕНЬ / 'Фикстуры']:
        if каталог.is_symlink() or not каталог.is_dir():
            raise SystemExit('КЛАВИАТУРА: неверный корень пакета')
    имена = ['Package.swift', 'определение.json', 'Фикстуры/переходы.json']
    if os.environ.get('KLAVIATURA_RED') == '1':
        имена.append('Фикстуры/определение-RED.json')
    for имя in имена:
        файл = КОРЕНЬ / имя
        if файл.is_symlink() or not файл.is_file():
            raise SystemExit('КЛАВИАТУРА: неверный корень пакета')
    return str(КОРЕНЬ)


def основная():
    разбор = argparse.ArgumentParser()
    разбор.add_argument('--кэш', type=Path, required=True)
    разбор.add_argument('--выход', type=Path, required=True)
    параметры = разбор.parse_args()
    КОНТРАКТ.проверить_служебные_пути(параметры.кэш, параметры.выход)
    среда = dict(os.environ)
    среда['КЛАВИАТУРА_КОРЕНЬ_ПАКЕТА'] = проверенныйКорень()
    subprocess.run(['python3', '-B', str(КОРЕНЬ / 'Сценарии/собрать-определение.py'), '--проверить'], check=True)
    начало = time.perf_counter_ns()
    subprocess.run(['swift', 'test', '--package-path', str(КОРЕНЬ), '--scratch-path', str(параметры.кэш), '-j', '2'], env=среда, check=True)
    проверка = time.perf_counter_ns() - начало
    начало = time.perf_counter_ns()
    subprocess.run(['swift', 'build', '--package-path', str(КОРЕНЬ), '--scratch-path', str(параметры.кэш), '-j', '2', '-c', 'release', '--product', 'Klaviatura'], check=True)
    сборка = time.perf_counter_ns() - начало
    ответ = subprocess.check_output(['swift', 'build', '--package-path', str(КОРЕНЬ), '--scratch-path', str(параметры.кэш), '-c', 'release', '--show-bin-path'], text=True)
    программа = Path(ответ.strip()) / 'Klaviatura'
    вход = КОРЕНЬ / 'Фикстуры/последовательность-профиля.json'
    входы = прочитать_объект(вход)['входы']
    пары = []
    последняя = None
    with tempfile.TemporaryDirectory(prefix='klaviatura-профиль-') as временное:
        for номер in range(3):
            измерения = {}
            данныеПары = {}
            for режим in (['эталон', 'FUMA'] if номер % 2 == 0 else ['FUMA', 'эталон']):
                выход = Path(временное) / (str(номер) + '-' + режим + '.json')
                начало = time.perf_counter_ns()
                subprocess.run([str(программа), '--режим', режим, '--определение', str(КОРЕНЬ / 'определение.json'), '--вход', str(вход), '--выход', str(выход)], check=True)
                полный = time.perf_counter_ns() - начало
                результат = прочитать_объект(выход)
                проверить_прогон(результат, режим, входы)
                данныеПары[режим] = результат
                измерения[режим] = {'полный_процесс_нс': полный, **результат['профиль']}
            if not равны(данныеПары['FUMA']['входы'], данныеПары['эталон']['входы']) or not равны(данныеПары['FUMA']['выходы'], данныеПары['эталон']['выходы']):
                raise SystemExit('FUMA расходится с независимым Swift-эталоном')
            пары.append({'эталон': измерения['эталон'], 'интерпретатор': измерения['FUMA']})
            последняя = данныеПары['FUMA']
    библиотека = КОРЕНЬ.parents[3] / 'Прототипы/память-структурирующих-операторов'
    хэшиБиблиотеки = {имя: hashlib.sha256((библиотека / имя).read_bytes()).hexdigest()
        for имя in исходники_интерпретатора(библиотека)}
    результат = {'схема': 'klaviatura.профиль.2', 'статус': 'измерен', 'условия': {'система': platform.system(), 'архитектура': platform.machine(), 'версия_компилятора': subprocess.check_output(['swift', '--version'], text=True).strip(), 'процессов_сборки': 2, 'пар': 3, 'прогрев': 'один переход вне внутреннего таймера', 'память': 'пик RSS отдельного процесса; включает запуск, разбор и переходы'}, 'хэши_исходников': {имя: hashlib.sha256((КОРЕНЬ / имя).read_bytes()).hexdigest() for имя in ИСХОДНИКИ}, 'хэши_интерпретатора': хэшиБиблиотеки, 'тесты_нс': проверка, 'сборка_выпуска_нс': сборка, 'пары': пары, 'полный_вход': последняя['входы'], 'полный_выход': последняя['выходы'], 'нативные_наблюдения': последняя['наблюдения'], 'совпадение': True, 'оптимизация': {'статус': 'требуется решение по измерениям', 'основание': 'Парные значения сохранены; ускорение полного приложения этим сценарием не измеряется'}}
    результат['хэш_бинарника'] = hashlib.sha256(программа.read_bytes()).hexdigest()
    проверить_профиль(результат)
    КОНТРАКТ.записать_результат(параметры.выход, результат)


if __name__ == '__main__':
    основная()

import Foundation
import XCTest
@testable import СтатистикаВызовов

final class ТестыГраницыУчёта: XCTestCase {
    func testНулевойБайтНеУсекаетЯвныйПуть() throws {
        try сФайлом(метаданные() + вызов()) { путь in
            let варианты = [
                URL(fileURLWithPath: путь.path + "\u{0}другой"),
                URL(string: путь.absoluteString + "%00другой")!
            ]
            for вариант in варианты {
                XCTAssertThrowsError(try прочитатьПрефикс(вариант, задача: задачаФикстуры))
            }
        }
    }
    func testДекодированныеПоляПроверяютсяДоИзмененияУчёта() throws {
        let исходное = try сводка(метаданные() + вызов()).наблюдения[0]
        let изменения: [(inout [String: Any]) -> Void] = [
            { $0["идентификатор"] = "невалидный ключ" },
            { $0["инструмент"] = String(repeating: "a", count: 257) },
            { $0["момент"] = ["качество": "известно", "наносекундыОтЭпохи": Int64.min] },
            { $0["момент"] = ["качество": "известно", "наносекундыОтЭпохи": Int64.max] },
            { $0["момент"] = ["качество": "неверно", "наносекундыОтЭпохи": 1] },
            { $0["момент"] = ["качество": "известно"] },
            { var п = $0["происхождение"] as! [String: Any]; п["начало"] = -1; $0["происхождение"] = п },
            { var п = $0["происхождение"] as! [String: Any]; п["конец"] = 0; $0["происхождение"] = п },
            { var п = $0["происхождение"] as! [String: Any]; п["строка"] = 0; $0["происхождение"] = п },
            { var п = $0["происхождение"] as! [String: Any]; п["sha256"] = "bad"; $0["происхождение"] = п },
            { var п = $0["происхождение"] as! [String: Any]; п["контракт"] = "другой"; $0["происхождение"] = п },
            { $0["направление"] = "результат" }
        ]
        for изменить in изменения {
            var объект = try JSONSerialization.jsonObject(with: кодироватьСтатистику(исходное)) as! [String: Any]
            изменить(&объект)
            let событие = try JSONDecoder().decode(СобытиеВызова.self, from: JSONSerialization.data(withJSONObject: объект))
            var учёт = try УчётВызовов(задача: задачаФикстуры)
            let до = учёт.отчёт()
            XCTAssertThrowsError(try учёт.принять([событие]))
            XCTAssertEqual(учёт.отчёт().наблюдения, до.наблюдения)
        }
    }
    func test_ПоддельныйХэшНеСкрываетИзменениеСемантики() throws {
        let исходное = try сводка(метаданные() + вызов()).наблюдения[0]
        var объект = try JSONSerialization.jsonObject(with: кодироватьСтатистику(исходное)) as! [String: Any]
        объект["инструмент"] = "tools.other"
        let событие = try JSONDecoder().decode(СобытиеВызова.self, from: JSONSerialization.data(withJSONObject: объект))
        var учёт = try УчётВызовов(задача: задачаФикстуры)
        try учёт.принять([исходное])
        let до = учёт.отчёт()
        XCTAssertThrowsError(try учёт.принять([событие]))
        XCTAssertEqual(учёт.отчёт(), до)
    }
}

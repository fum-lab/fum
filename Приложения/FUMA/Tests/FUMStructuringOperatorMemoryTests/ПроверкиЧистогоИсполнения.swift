      "--определение", "пример.json", "--вход", "текст",
    ])
    XCTAssertThrowsError(try текстовые.значение(Data([0xC0, 0xAF])))
    let канал = Pipe()
    try канал.fileHandleForWriting.write(contentsOf: Data([1, 2, 3]))
    try канал.fileHandleForWriting.close()
    XCTAssertThrowsError(try КонечныйВвод.прочитать(канал.fileHandleForReading, предел: 2))
  }

  func test_ОпределениеМеняетПоведениеИИдентичность() throws {
    let исходное = try определениеБайтов()
    let правило = ПравилоБайтов(
      идентификатор: "низкие-биты",
      байты: [ДиапазонБайта(от: 0, до: 127)],
      поля: [БитовоеПоле(байт: 0, маска: 63, сдвиг: 0)])
    let другое = ОпределениеОператора(
      идентификатор: "другая-маска", версия: 1,
      правила: [правило],
      шаги: [
        ШагОператора(
          идентификатор: "читать",
          действие: .повторитьПравила(["низкие-биты"]))
      ])
    XCTAssertEqual(
      try AutomationExecutor.выполнить(другое, вход: .байты([65])).результат, .скаляры([1]))
    XCTAssertEqual(try AutomationExecutor.выполнить(исходное, вход: .байты([65])).скаляры, [65])
    let обрезать = ШагОператора(идентификатор: "края", действие: .обрезать)
    let пробелы = ШагОператора(идентификатор: "пробелы", действие: .сжатьПробелы)
    let определения = [
      ОпределениеОператора(идентификатор: "пример", версия: 1, шаги: [обрезать, пробелы]),
      ОпределениеОператора(идентификатор: "пример", версия: 2, шаги: [обрезать, пробелы]),
      ОпределениеОператора(идентификатор: "пример", версия: 1, шаги: [пробелы, обрезать]),
      ОпределениеОператора(
        идентификатор: "пример", версия: 1,
        шаги: [
          ШагОператора(идентификатор: "замена", действие: .заменить("а", "б"))
        ]),
      ОпределениеОператора(
        идентификатор: "пример", версия: 1,
        шаги: [
          ШагОператора(идентификатор: "замена", действие: .заменить("а", "в"))
        ]),
    ]
    let наблюдения = try определения.map {
      try AutomationExecutor.выполнить($0, вход: .текст("пример"))
    }
    XCTAssertTrue(наблюдения.allSatisfy { $0.результат == .текст("пример") })
    XCTAssertEqual(Set(наблюдения.map(\.хэшОпределения)).count, определения.count)
    XCTAssertEqual(Set(наблюдения.map(\.хэшНаблюдения)).count, определения.count)
  }

  func test_ОжиданиеПринадлежитТолькоСтаромуАдаптеру() throws {
    let шаги = [AutomationStep(id: "края", kind: .trim, argument: nil)]
    let верно = try AutomationExecutor.run(
      AutomationFixture(
        operatorId: "пример", input: " а ",
        expectedOutput: "а", effects: [], steps: шаги))
    let неверно = try AutomationExecutor.run(
      AutomationFixture(
        operatorId: "пример", input: " а ",
        expectedOutput: "б", effects: [], steps: шаги))
    XCTAssertTrue(верно.passed)
    XCTAssertFalse(неверно.passed)
    XCTAssertEqual(верно.output, неверно.output)
    XCTAssertEqual(верно.steps, неверно.steps)
  }

  func test_ПрежниеПустыеИПовторныеШагиАдаптера() throws {

  func test_КаноническиеБайтыТипизированныхЗначений() throws {
    XCTAssertEqual(
      String(
        decoding: try каноническиеДанные(ЗначениеОператора.байты([0, 65, 255])), as: UTF8.self),
      "{\"значение\":[0,65,255],\"тип\":\"байты\"}")
    XCTAssertEqual(
      String(
        decoding: try каноническиеДанные(ЗначениеОператора.скаляры([0, 1105, 1_114_111])),
        as: UTF8.self),
      "{\"значение\":[0,1105,1114111],\"тип\":\"скаляры\"}")
    XCTAssertEqual(
      ЗначениеОператора.скаляры([0, 1105, 1_114_111]).исходныеБайты,
      Data([0, 0, 0, 0, 0, 0, 4, 81, 0, 16, 255, 255]))
  }
  private func определениеБайтов() throws -> ОпределениеОператора {
    try ОпределениеОператора.разобрать(
      РесурсыОпределений.прочитать("UTF-8-в-UTF-32LE"))
  }

  private func байты(_ запись: String) -> [UInt8] {
    запись.split(separator: " ").map { UInt8($0, radix: 16)! }
  }

  func test_КонечныйВводИзПотокаИЗакрытыеПараметры() throws {

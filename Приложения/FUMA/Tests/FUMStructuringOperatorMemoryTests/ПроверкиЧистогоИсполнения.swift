  func test_НеоднозначныеПравилаИПределСтруктуры() throws {
    let одно = ПравилоБайтов(
      идентификатор: "одно", байты: [ДиапазонБайта(от: 0, до: 127)],
      поля: [БитовоеПоле(байт: 0, маска: 127, сдвиг: 0)])
    let два = ПравилоБайтов(
      идентификатор: "два", байты: [ДиапазонБайта(от: 65, до: 127), ДиапазонБайта(от: 0, до: 255)],
      поля: [БитовоеПоле(байт: 0, маска: 127, сдвиг: 0)])
    let определение = ОпределениеОператора(
      идентификатор: "пример", версия: 1,
      правила: [одно, два],
      шаги: [ШагОператора(идентификатор: "повтор", действие: .повторитьПравила(["одно", "два"]))])
    XCTAssertThrowsError(try AutomationExecutor.выполнить(определение, вход: .байты([65, 66])))
    XCTAssertThrowsError(try ОпределениеОператора.разобрать(Data(repeating: 32, count: 65_537)))
    XCTAssertThrowsError(
      try ОпределениеОператора.разобрать(
        Data((String(repeating: "[", count: 18) + "0" + String(repeating: "]", count: 18)).utf8)))
    for текст in [
      "{\"версия\":01}", "{\"версия\":1.0}", "{\"версия\":null}", "{\"версия\":-}",
      "{\"версия\":1,}", "{\"версия\":\"\\ud800\"}",
    ] {
      XCTAssertThrowsError(try ОпределениеОператора.разобрать(Data(текст.utf8)))
    }
  }

  func test_НедопустимыеОпределенияИБюджеты() throws {
    let исходное = try определениеБайтов()
    let шаг = исходное.шаги[0]
    let ошибочные = [
      ОпределениеОператора(идентификатор: "пример", версия: 0, шаги: [шаг]),
      ОпределениеОператора(
        идентификатор: "пример", версия: 1, правила: исходное.правила, шаги: [шаг, шаг]),
      ОпределениеОператора(идентификатор: "пример", версия: 1, правила: [], шаги: [шаг]),
      ОпределениеОператора(
        идентификатор: "пример", версия: 1, правила: исходное.правила + [исходное.правила[0]],
        шаги: [шаг]),
      ОпределениеОператора(
        идентификатор: "пример", версия: 1,
        шаги: [
          ШагОператора(идентификатор: "пусто", действие: .заменить("", "а"))
        ]),
    ]
    for определение in ошибочные {
      XCTAssertThrowsError(try AutomationExecutor.выполнить(определение, вход: .байты([])))
    }
    for (диапазоны, поля) in [
      ([ДиапазонБайта](), [БитовоеПоле(байт: 0, маска: 1, сдвиг: 0)]),
      ([ДиапазонБайта(от: 0, до: 255)], [БитовоеПоле(байт: 1, маска: 1, сдвиг: 0)]),
      ([ДиапазонБайта(от: 0, до: 255)], [БитовоеПоле(байт: 0, маска: 255, сдвиг: 31)]),
      ([ДиапазонБайта(от: 0, до: 255)], [БитовоеПоле(байт: 0, маска: 0, сдвиг: 0)]),
    ] {
      let правило = ПравилоБайтов(идентификатор: "правило", байты: диапазоны, поля: поля)
      let определение = ОпределениеОператора(
        идентификатор: "пример", версия: 1,
        правила: [правило],
        шаги: [
          ШагОператора(
            идентификатор: "повтор",
            действие: .повторитьПравила(["правило"]))
        ])
      XCTAssertThrowsError(try AutomationExecutor.выполнить(определение, вход: .байты([])))
    }
    XCTAssertThrowsError(
      try AutomationExecutor.выполнить(
        исходное,
        вход: .байты([65]), пределы: ПределыИсполнения(операций: 1)))
    XCTAssertThrowsError(
      try AutomationExecutor.выполнить(
        исходное,
        вход: .байты([]), пределы: ПределыИсполнения(записейТрассы: 257)))
    XCTAssertEqual(
      try AutomationExecutor.выполнить(
        исходное, вход: .байты([65]),
        пределы: ПределыИсполнения(байтовВхода: 1, байтовРезультата: 4)
      ).результат, .байты([65, 0, 0, 0]))
    for скаляр: UInt32 in [0xD800, 0xDFFF, 0x110000, UInt32.max] {
      let упаковка = ОпределениеОператора(
        идентификатор: "пример", версия: 1,
        шаги: [исходное.шаги[1]])
      XCTAssertThrowsError(try AutomationExecutor.выполнить(упаковка, вход: .скаляры([скаляр])))
    }
  }

  func test_НезависимыеГраницыСкаляровИОбаПорядка() throws {
    let ожидания: [(String, UInt32, String, String)] = [
      ("00", 0, "00 00 00 00", "00 00 00 00"),
      ("7F", 0x7F, "7F 00 00 00", "00 00 00 7F"),
      ("C2 80", 0x80, "80 00 00 00", "00 00 00 80"),
      ("DF BF", 0x7FF, "FF 07 00 00", "00 00 07 FF"),
      ("E0 A0 80", 0x800, "00 08 00 00", "00 00 08 00"),
      ("E0 BF BF", 0xFFF, "FF 0F 00 00", "00 00 0F FF"),
      ("E1 80 80", 0x1000, "00 10 00 00", "00 00 10 00"),
      ("EC BF BF", 0xCFFF, "FF CF 00 00", "00 00 CF FF"),
      ("ED 80 80", 0xD000, "00 D0 00 00", "00 00 D0 00"),
      ("ED 9F BF", 0xD7FF, "FF D7 00 00", "00 00 D7 FF"),
      ("EE 80 80", 0xE000, "00 E0 00 00", "00 00 E0 00"),
      ("EF BF BF", 0xFFFF, "FF FF 00 00", "00 00 FF FF"),
      ("F0 90 80 80", 0x10000, "00 00 01 00", "00 01 00 00"),
      ("F0 BF BF BF", 0x3FFFF, "FF FF 03 00", "00 03 FF FF"),
      ("F1 80 80 80", 0x40000, "00 00 04 00", "00 04 00 00"),
      ("F3 BF BF BF", 0xFFFFF, "FF FF 0F 00", "00 0F FF FF"),
      ("F4 80 80 80", 0x100000, "00 00 10 00", "00 10 00 00"),
      ("F4 8F BF BF", 0x10FFFF, "FF FF 10 00", "00 10 FF FF"),
      ("D1 91", 0x451, "51 04 00 00", "00 00 04 51"),
      ("F0 9F 99 82", 0x1F642, "42 F6 01 00", "00 01 F6 42"),
      ("EF B7 90", 0xFDD0, "D0 FD 00 00", "00 00 FD D0"),
      ("EF BF BE", 0xFFFE, "FE FF 00 00", "00 00 FF FE"),
      ("EF BB BF", 0xFEFF, "FF FE 00 00", "00 00 FE FF"),
    ]
    let исходное = try определениеБайтов()
    for (вход, скаляр, младшие, старшие) in ожидания {
      for (порядок, выход) in [(ПорядокБайтов.младшийПервым, младшие), (.старшийПервым, старшие)] {
        let определение = ОпределениеОператора(
          идентификатор: исходное.идентификатор, версия: 1,
          правила: исходное.правила,
          шаги: [
            исходное.шаги[0],
            ШагОператора(
              идентификатор: "выход",
              действие: .упаковатьСлова(ширина: 4, порядок: порядок)),
          ])
        let наблюдение = try AutomationExecutor.выполнить(определение, вход: .байты(байты(вход)))
        XCTAssertEqual(наблюдение.скаляры, [скаляр], вход)
        XCTAssertEqual(наблюдение.результат, .байты(байты(выход)), вход)
      }
    }
    let пусто = try AutomationExecutor.выполнить(исходное, вход: .байты([]))
    XCTAssertEqual(пусто.результат, .байты([]))
    let разложенное = try AutomationExecutor.выполнить(исходное, вход: .байты(байты("65 CC 81")))
    XCTAssertEqual(разложенное.скаляры, [0x65, 0x301])
    XCTAssertEqual(разложенное.результат, .байты(байты("65 00 00 00 01 03 00 00")))
  }

  func test_СтрогиеОтказыСАбсолютнымиПозициями() throws {
    let ожидания: [(String, Int, Int)] = [
      ("80", 0, 0), ("BF", 0, 0), ("C0 AF", 0, 0), ("C1 BF", 0, 0),
      ("E0 9F 80", 1, 0), ("ED A0 80", 1, 0), ("ED BF BF", 1, 0),
      ("F0 8F BF BF", 1, 0), ("F4 90 80 80", 1, 0), ("F5 80 80 80", 0, 0),
      ("FF", 0, 0), ("D1", 1, 0), ("E0", 1, 0), ("E0 A0", 2, 0),
      ("F0", 1, 0), ("F0 90", 2, 0), ("F0 90 80", 3, 0),
      ("C2 7F", 1, 0), ("E1 C0 80", 1, 0), ("E1 80 7F", 2, 0),
      ("F1 80 C0 80", 2, 0), ("F1 80 80 C0", 3, 0),
      ("41 80", 1, 1), ("41 C2 42", 2, 1), ("D1 91 F0 90 80", 5, 2),
      ("F8 88 80 80 80", 0, 0),
    ]
    for (вход, позиция, начало) in ожидания {
      XCTAssertThrowsError(
        try AutomationExecutor.выполнить(
          определениеБайтов(), вход: .байты(байты(вход)))
      ) { ошибка in
        guard let отказ = ошибка as? ОшибкаИсполнения else {
          return XCTFail("Нет типизированного отказа")
        }
        XCTAssertEqual(отказ.позицияБайта, позиция, вход)
        XCTAssertEqual(отказ.началоПоследовательности, начало, вход)
      }
    }
  }

  func test_ЗакрытыйРазборИПовторЭкранированногоПоля() throws {
    let исходные = try РесурсыОпределений.прочитать("UTF-8-в-UTF-32LE")
    let текст = String(decoding: исходные, as: UTF8.self)
    for повреждённый in [
      текст.replacingOccurrences(of: "\"версия\": 1", with: "\"версия\": 1, \"\\u0432ерсия\": 2"),
      текст.replacingOccurrences(of: "\"версия\": 1", with: "\"версия\": true"),
      текст.replacingOccurrences(of: "\"версия\": 1", with: "\"версия\": 1, \"лишнее\": 0"),
      текст.replacingOccurrences(of: "\"маска\": 63", with: "\"маска\": 256"),
    ] {
      XCTAssertNotEqual(повреждённый, текст)
      XCTAssertThrowsError(try ОпределениеОператора.разобрать(Data(повреждённый.utf8)))
    }
  }

  func test_ОграниченнаяТрассаИСвязьТочногоВхода() throws {
    let определение = try определениеБайтов()
    let наблюдение = try AutomationExecutor.выполнить(
      определение,
      вход: .байты([65, 66, 67]), пределы: ПределыИсполнения(записейТрассы: 1))
    XCTAssertEqual(наблюдение.скаляры, [65, 66, 67])
    XCTAssertEqual(наблюдение.трасса.count, 1)
    XCTAssertEqual(наблюдение.пропущеноЗаписей, 2)
    XCTAssertEqual(наблюдение.хэшИсходныхБайтов, sha256Digest(Data([65, 66, 67])))
    XCTAssertThrowsError(
      try AutomationExecutor.выполнить(
        определение,
        вход: .байты([65, 66, 67]), пределы: ПределыИсполнения(байтовВхода: 2)))
    XCTAssertThrowsError(
      try AutomationExecutor.выполнить(
        определение,
        вход: .байты([65]), пределы: ПределыИсполнения(байтовРезультата: 3)))
  }


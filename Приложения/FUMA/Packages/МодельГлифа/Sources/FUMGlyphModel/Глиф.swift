    self.значение = значение
  }

  public init(from декодер: Decoder) throws {
    let контейнер = try декодер.singleValueContainer()
    значение = try контейнер.decode(UInt32.self)
  }

  public func encode(to кодировщик: Encoder) throws {
    var контейнер = кодировщик.singleValueContainer()
    try контейнер.encode(значение)
  }
}


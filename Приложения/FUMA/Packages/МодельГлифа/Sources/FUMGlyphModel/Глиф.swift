/// Скалярное значение, отличное от графемного кластера Swift `Character`.
public struct Скаляр: Hashable, Sendable, Codable, CustomStringConvertible {
  public let значение: UInt32

  public init?(_ значение: UInt32) {
    guard Unicode.Scalar(значение) != nil else { return nil }
    self.значение = значение
  }

  public init?(_ запись: String) {
    guard запись.hasPrefix("U+"),
      let значение = UInt32(запись.dropFirst(2), radix: 16)
    else { return nil }
    self.init(значение)
  }

  public var description: String {
    let цифры = String(значение, radix: 16, uppercase: true)
    return "U+" + String(repeating: "0", count: max(0, 4 - цифры.count)) + цифры
  }

  public init(from декодер: Decoder) throws {
    let контейнер = try декодер.singleValueContainer()
    let запись = try контейнер.decode(String.self)
    guard let скаляр = Скаляр(запись) else {
      throw DecodingError.dataCorruptedError(
        in: контейнер,
        debugDescription: "Ожидается скалярное значение в записи U+ с шестнадцатеричными цифрами."
      )
    }
    self = скаляр
  }

  public func encode(to кодировщик: Encoder) throws {
    var контейнер = кодировщик.singleValueContainer()
    try контейнер.encode(description)
  }
}

/// Координаты и метрики выражаются в единицах сетки дизайна выбранного набора глифов.
public struct МетрикиГлифа: Equatable, Sendable, Codable {
  public let ширинаПродвижения: Int32
  public let левыйБоковойВынос: Int32

  public init(ширинаПродвижения: Int32, левыйБоковойВынос: Int32) {
    self.ширинаПродвижения = ширинаПродвижения
    self.левыйБоковойВынос = левыйБоковойВынос
  }
}

/// Порядок точек значим. `наКривой == false` помечает контрольную точку квадратичной кривой;
/// контур замыкается неявно. Модель не вычисляет промежуточные точки и не рисует контуры.
public struct ТочкаГлифа: Equatable, Sendable, Codable {
  public let идентификатор: ИдентификаторТочки
  public let икс: Int32
  public let игрек: Int32
  public let наКривой: Bool

  public init(
    идентификатор: ИдентификаторТочки,
    икс: Int32,
    игрек: Int32,
    наКривой: Bool
  ) {
    self.идентификатор = идентификатор
    self.икс = икс
    self.игрек = игрек
    self.наКривой = наКривой
  }
}

public struct КонтурГлифа: Equatable, Sendable, Codable {
  public let идентификатор: ИдентификаторКонтура
  public let точки: [ТочкаГлифа]

  public init(идентификатор: ИдентификаторКонтура, точки: [ТочкаГлифа]) {
    self.идентификатор = идентификатор
    self.точки = точки
  }
}

public struct КонтурыГлифа: Equatable, Sendable, Codable {
  public let контуры: [КонтурГлифа]

  public init(контуры: [КонтурГлифа] = []) {
    self.контуры = контуры
  }
}

public struct Глиф: Equatable, Sendable, Codable {
  public let идентификатор: ИдентификаторГлифа
  public let имя: String?
  public let метрики: МетрикиГлифа
  public let контурнаяМодель: КонтурыГлифа

  public init(
    идентификатор: ИдентификаторГлифа,
    имя: String? = nil,
    метрики: МетрикиГлифа,
    контурнаяМодель: КонтурыГлифа = КонтурыГлифа()
  ) {
    self.идентификатор = идентификатор
    self.имя = имя
    self.метрики = метрики
    self.контурнаяМодель = контурнаяМодель
  }
}

public struct СопоставлениеСкалярногоЗначения: Equatable, Sendable, Codable {
  public let скаляр: Скаляр
  public let идентификаторГлифа: ИдентификаторГлифа

  public init(скаляр: Скаляр, идентификаторГлифа: ИдентификаторГлифа) {
    self.скаляр = скаляр
    self.идентификаторГлифа = идентификаторГлифа
  }
}

public enum ОшибкаМоделиГлифа: Error, Equatable, Sendable {
  case повторныйИдентификаторГлифа(ИдентификаторГлифа)
  case повторныйИдентификаторКонтура(ИдентификаторКонтура)
  case повторныйИдентификаторТочки(ИдентификаторТочки)
  case повторныйСкаляр(Скаляр)
  case пустойКонтур(ИдентификаторКонтура)
  case глифНеНайден(ИдентификаторГлифа)
  case контурНеНайден(ИдентификаторКонтура)
  case точкаНеНайдена(ИдентификаторТочки)
  case сопоставлениеСсылаетсяНаОтсутствующийГлиф(ИдентификаторГлифа)
  case индексТочкиВнеГраниц
  case нельзяУдалитьПоследнююТочку
}

/// Изменяемые глифы и таблица «один скаляр — один глиф».
/// Комбинирующий скаляр остаётся отдельной записью; это не текстовый шейпинг.
public struct МодельРедактированияГлифов: Sendable {
  private var глифыПоИдентификатору: [ИдентификаторГлифа: Глиф]
  public private(set) var сопоставленияСкалярныхЗначений: [Скаляр: ИдентификаторГлифа]

  public init(глифы: [Глиф], сопоставления: [СопоставлениеСкалярногоЗначения]) throws {
    var глифыПоИдентификатору: [ИдентификаторГлифа: Глиф] = [:]
    for глиф in глифы {
      guard глифыПоИдентификатору[глиф.идентификатор] == nil else {
        throw ОшибкаМоделиГлифа.повторныйИдентификаторГлифа(глиф.идентификатор)
      }
      try Self.проверитьКонтуры(глиф.контурнаяМодель)
      глифыПоИдентификатору[глиф.идентификатор] = глиф
    }

    var сопоставленияСкалярныхЗначений: [Скаляр: ИдентификаторГлифа] = [:]
    for сопоставление in сопоставления {
      guard сопоставленияСкалярныхЗначений[сопоставление.скаляр] == nil else {
        throw ОшибкаМоделиГлифа.повторныйСкаляр(сопоставление.скаляр)
      }
      guard глифыПоИдентификатору[сопоставление.идентификаторГлифа] != nil else {
        throw ОшибкаМоделиГлифа.сопоставлениеСсылаетсяНаОтсутствующийГлиф(
          сопоставление.идентификаторГлифа
        )
      }
      сопоставленияСкалярныхЗначений[сопоставление.скаляр] = сопоставление.идентификаторГлифа
    }

    self.глифыПоИдентификатору = глифыПоИдентификатору
    self.сопоставленияСкалярныхЗначений = сопоставленияСкалярныхЗначений
  }

  public func найтиГлиф(идентификатор: ИдентификаторГлифа) -> Глиф? {
    глифыПоИдентификатору[идентификатор]
  }

  public var идентификаторыГлифов: Set<ИдентификаторГлифа> {
    Set(глифыПоИдентификатору.keys)
  }

  public mutating func переместитьТочку(
    идентификаторГлифа: ИдентификаторГлифа,
    идентификаторТочки: ИдентификаторТочки,
    вИкс икс: Int32,
    игрек: Int32
  ) throws {
    let глиф = try требуемыйГлиф(идентификатор: идентификаторГлифа)
    var контуры = глиф.контурнаяМодель.контуры
    for индексКонтура in контуры.indices {
      var точки = контуры[индексКонтура].точки
      guard let индексТочки = точки.firstIndex(where: { $0.идентификатор == идентификаторТочки }) else {
        continue
      }
      let точка = точки[индексТочки]
      точки[индексТочки] = ТочкаГлифа(
        идентификатор: точка.идентификатор,
        икс: икс,
        игрек: игрек,
        наКривой: точка.наКривой
      )
      контуры[индексКонтура] = КонтурГлифа(
        идентификатор: контуры[индексКонтура].идентификатор,
        точки: точки
      )
      глифыПоИдентификатору[идентификаторГлифа] = Глиф(
        идентификатор: глиф.идентификатор,
        имя: глиф.имя,
        метрики: глиф.метрики,
        контурнаяМодель: КонтурыГлифа(контуры: контуры)
      )
      return
    }
    throw ОшибкаМоделиГлифа.точкаНеНайдена(идентификаторТочки)
  }

  public mutating func вставитьТочку(
    _ точка: ТочкаГлифа,
    вКонтур идентификаторКонтура: ИдентификаторКонтура,
    глифа идентификаторГлифа: ИдентификаторГлифа,
    поИндексу индекс: Int
  ) throws {
    let глиф = try требуемыйГлиф(идентификатор: идентификаторГлифа)
    guard !глиф.контурнаяМодель.контуры.contains(
      where: { $0.точки.contains(where: { $0.идентификатор == точка.идентификатор }) }
    ) else {
      throw ОшибкаМоделиГлифа.повторныйИдентификаторТочки(точка.идентификатор)
    }
    guard let индексКонтура = глиф.контурнаяМодель.контуры.firstIndex(
      where: { $0.идентификатор == идентификаторКонтура }
    ) else {
      throw ОшибкаМоделиГлифа.контурНеНайден(идентификаторКонтура)
    }
    var контуры = глиф.контурнаяМодель.контуры
    var точки = контуры[индексКонтура].точки
    guard (0...точки.count).contains(индекс) else {
      throw ОшибкаМоделиГлифа.индексТочкиВнеГраниц
    }
    точки.insert(точка, at: индекс)
    контуры[индексКонтура] = КонтурГлифа(идентификатор: идентификаторКонтура, точки: точки)
    глифыПоИдентификатору[идентификаторГлифа] = Глиф(
      идентификатор: глиф.идентификатор,
      имя: глиф.имя,
      метрики: глиф.метрики,
      контурнаяМодель: КонтурыГлифа(контуры: контуры)
    )
  }

  public mutating func удалитьТочку(
    _ идентификаторТочки: ИдентификаторТочки,
    изКонтура идентификаторКонтура: ИдентификаторКонтура,
    глифа идентификаторГлифа: ИдентификаторГлифа
  ) throws {
    let глиф = try требуемыйГлиф(идентификатор: идентификаторГлифа)
    guard let индексКонтура = глиф.контурнаяМодель.контуры.firstIndex(
      where: { $0.идентификатор == идентификаторКонтура }
    ) else {
      throw ОшибкаМоделиГлифа.контурНеНайден(идентификаторКонтура)
    }
    var контуры = глиф.контурнаяМодель.контуры
    var точки = контуры[индексКонтура].точки
    guard let индексТочки = точки.firstIndex(where: { $0.идентификатор == идентификаторТочки }) else {
      throw ОшибкаМоделиГлифа.точкаНеНайдена(идентификаторТочки)
    }
    guard точки.count > 1 else { throw ОшибкаМоделиГлифа.нельзяУдалитьПоследнююТочку }
    точки.remove(at: индексТочки)
    контуры[индексКонтура] = КонтурГлифа(идентификатор: идентификаторКонтура, точки: точки)
    глифыПоИдентификатору[идентификаторГлифа] = Глиф(
      идентификатор: глиф.идентификатор,
      имя: глиф.имя,
      метрики: глиф.метрики,
      контурнаяМодель: КонтурыГлифа(контуры: контуры)
    )
  }

  public mutating func установитьСопоставление(
    для скаляр: Скаляр,
    в идентификаторГлифа: ИдентификаторГлифа?
  ) throws {
    guard let идентификаторГлифа else {
      сопоставленияСкалярныхЗначений.removeValue(forKey: скаляр)
      return
    }
    guard глифыПоИдентификатору[идентификаторГлифа] != nil else {
      throw ОшибкаМоделиГлифа.сопоставлениеСсылаетсяНаОтсутствующийГлиф(идентификаторГлифа)
    }
    сопоставленияСкалярныхЗначений[скаляр] = идентификаторГлифа
  }

  private func требуемыйГлиф(идентификатор: ИдентификаторГлифа) throws -> Глиф {
    guard let глиф = глифыПоИдентификатору[идентификатор] else {
      throw ОшибкаМоделиГлифа.глифНеНайден(идентификатор)
    }
    return глиф
  }

  private static func проверитьКонтуры(_ модель: КонтурыГлифа) throws {
    var идентификаторыКонтуров: Set<ИдентификаторКонтура> = []
    var идентификаторыТочек: Set<ИдентификаторТочки> = []
    for контур in модель.контуры {
      guard идентификаторыКонтуров.insert(контур.идентификатор).inserted else {
        throw ОшибкаМоделиГлифа.повторныйИдентификаторКонтура(контур.идентификатор)
      }
      guard !контур.точки.isEmpty else {
        throw ОшибкаМоделиГлифа.пустойКонтур(контур.идентификатор)
      }
      for точка in контур.точки {
        guard идентификаторыТочек.insert(точка.идентификатор).inserted else {
          throw ОшибкаМоделиГлифа.повторныйИдентификаторТочки(точка.идентификатор)
        }
      }
    }
  }
}

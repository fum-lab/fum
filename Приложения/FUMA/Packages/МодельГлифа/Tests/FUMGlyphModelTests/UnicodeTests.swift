import Foundation
import XCTest
@testable import МодельГлифа

final class ПроверкиСкалярныхЗначений: XCTestCase {
  func test_СопоставляетСкалярРаздельноБезСхлопыванияКомбинирующегоЗнака() throws {
    let адрес = try XCTUnwrap(
      Bundle.module.url(
        forResource: "сопоставление-unicode",
        withExtension: "json",
        subdirectory: "Фикстуры"
      )
    )
    let фикстура = try JSONDecoder().decode(
      ФикстураСопоставлений.self,
      from: Data(contentsOf: адрес)
    )
    let основа = Глиф(
      идентификатор: ИдентификаторГлифа(7),
      метрики: .init(ширинаПродвижения: 400, левыйБоковойВынос: 0)
    )
    let знак = Глиф(
      идентификатор: ИдентификаторГлифа(8),
      метрики: .init(ширинаПродвижения: 0, левыйБоковойВынос: 0)
    )
    let модель = try МодельРедактированияГлифов(
      глифы: [основа, знак],
      сопоставления: фикстура.сопоставления
    )

    XCTAssertEqual(модель.сопоставленияСкалярныхЗначений.count, 2)
    XCTAssertEqual(
      модель.сопоставленияСкалярныхЗначений[try XCTUnwrap(Скаляр("U+0065"))],
      ИдентификаторГлифа(7)
    )
    XCTAssertEqual(
      модель.сопоставленияСкалярныхЗначений[try XCTUnwrap(Скаляр("U+0301"))],
      ИдентификаторГлифа(8)
    )
  }

  func test_ОтклоняетПриДекодированииСуррогатныйКодИПринимаетВерхнююГраницу() throws {
    XCTAssertThrowsError(
      try JSONDecoder().decode(Скаляр.self, from: Data("\"U+D800\"".utf8))
    )
    XCTAssertNil(Скаляр(0xD800))
    XCTAssertNil(Скаляр(0x110000))

    let верхняяГраница = try JSONDecoder().decode(
      Скаляр.self,
      from: Data("\"U+10FFFF\"".utf8)
    )
    XCTAssertEqual(верхняяГраница.значение, 0x10FFFF)
  }

  func test_ОтклоняетСопоставлениеНаНесуществующийГлиф() throws {
    let скаляр = try XCTUnwrap(Скаляр(0x0065))
    let глиф = Глиф(
      идентификатор: ИдентификаторГлифа(7),
      метрики: .init(ширинаПродвижения: 400, левыйБоковойВынос: 0)
    )

    XCTAssertThrowsError(
      try МодельРедактированияГлифов(
        глифы: [глиф],
        сопоставления: [СопоставлениеСкалярногоЗначения(
          скаляр: скаляр,
          идентификаторГлифа: ИдентификаторГлифа(99)
        )]
      )
    ) {
      XCTAssertEqual(
        $0 as? ОшибкаМоделиГлифа,
        .сопоставлениеСсылаетсяНаОтсутствующийГлиф(ИдентификаторГлифа(99))
      )
    }
  }

  func test_ОтклоняетПовторСкалярногоЗначенияИПовторныйИдентификаторГлифа() throws {
    let скаляр = try XCTUnwrap(Скаляр(0x0065))
    let глиф = Глиф(
      идентификатор: ИдентификаторГлифа(7),
      метрики: .init(ширинаПродвижения: 400, левыйБоковойВынос: 0)
    )
    XCTAssertThrowsError(
      try МодельРедактированияГлифов(глифы: [глиф, глиф], сопоставления: [])
    ) {
      XCTAssertEqual(
        $0 as? ОшибкаМоделиГлифа,
        .повторныйИдентификаторГлифа(ИдентификаторГлифа(7))
      )
    }
    XCTAssertThrowsError(
      try МодельРедактированияГлифов(
        глифы: [глиф],
        сопоставления: [
          СопоставлениеСкалярногоЗначения(скаляр: скаляр, идентификаторГлифа: глиф.идентификатор),
          СопоставлениеСкалярногоЗначения(скаляр: скаляр, идентификаторГлифа: глиф.идентификатор),
        ]
      )
    ) {
      XCTAssertEqual($0 as? ОшибкаМоделиГлифа, .повторныйСкаляр(скаляр))
    }
  }

  func test_СопоставлениеМожноЗаменитьИУдалить() throws {
    let скаляр = try XCTUnwrap(Скаляр(0x0065))
    let первый = Глиф(
      идентификатор: ИдентификаторГлифа(7),
      метрики: .init(ширинаПродвижения: 400, левыйБоковойВынос: 0)
    )
    let второй = Глиф(
      идентификатор: ИдентификаторГлифа(8),
      метрики: .init(ширинаПродвижения: 0, левыйБоковойВынос: 0)
    )
    var модель = try МодельРедактированияГлифов(
      глифы: [первый, второй],
      сопоставления: [СопоставлениеСкалярногоЗначения(
        скаляр: скаляр,
        идентификаторГлифа: первый.идентификатор
      )]
    )

    try модель.установитьСопоставление(для: скаляр, в: второй.идентификатор)
    XCTAssertEqual(модель.сопоставленияСкалярныхЗначений[скаляр], второй.идентификатор)
    try модель.установитьСопоставление(для: скаляр, в: nil)
    XCTAssertNil(модель.сопоставленияСкалярныхЗначений[скаляр])
  }
}

private struct ФикстураСопоставлений: Decodable {
  let сопоставления: [СопоставлениеСкалярногоЗначения]
}

import Foundation
import XCTest
@testable import МодельГлифа

final class ПроверкиРедактирования: XCTestCase {
  func test_РедактированиеТочкиСохраняетИдентичностьИМетрики() throws {
    let глиф = try фикстура("глиф-простой-контур")
    var модель = try МодельРедактированияГлифов(глифы: [глиф], сопоставления: [])

    try модель.переместитьТочку(
      идентификаторГлифа: глиф.идентификатор,
      идентификаторТочки: ИдентификаторТочки(2),
      вИкс: 420,
      игрек: 15
    )

    let обновлённый = try XCTUnwrap(модель.найтиГлиф(идентификатор: глиф.идентификатор))
    XCTAssertEqual(обновлённый.идентификатор, глиф.идентификатор)
    XCTAssertEqual(обновлённый.метрики, глиф.метрики)
    XCTAssertEqual(обновлённый.контурнаяМодель.контуры[0].точки[1].идентификатор, ИдентификаторТочки(2))
    XCTAssertEqual(обновлённый.контурнаяМодель.контуры[0].точки[1].икс, 420)
    XCTAssertEqual(обновлённый.контурнаяМодель.контуры[0].точки[1].игрек, 15)
  }

  func test_ДобавляетИУдаляетТочкуСЯвнойСтабильнойИдентичностью() throws {
    let глиф = try фикстура("глиф-простой-контур")
    var модель = try МодельРедактированияГлифов(глифы: [глиф], сопоставления: [])
    let добавленная = ТочкаГлифа(
      идентификатор: ИдентификаторТочки(5), икс: 200, игрек: 250, наКривой: false
    )
    let идентификаторКонтура = ИдентификаторКонтура(1)

    try модель.вставитьТочку(
      добавленная,
      вКонтур: идентификаторКонтура,
      глифа: глиф.идентификатор,
      поИндексу: 2
    )
    XCTAssertEqual(
      модель.найтиГлиф(идентификатор: глиф.идентификатор)?
        .контурнаяМодель.контуры[0].точки[2],
      добавленная
    )

    try модель.удалитьТочку(
      ИдентификаторТочки(5),
      изКонтура: идентификаторКонтура,
      глифа: глиф.идентификатор
    )
    XCTAssertFalse(
      модель.найтиГлиф(идентификатор: глиф.идентификатор)?
        .контурнаяМодель.контуры[0].точки.contains { $0.идентификатор == ИдентификаторТочки(5) }
        ?? true
    )
  }

  func test_ОтклоняетУдалениеПоследнейТочкиКонтура() throws {
    let глиф = Глиф(
      идентификатор: ИдентификаторГлифа(9),
      метрики: МетрикиГлифа(ширинаПродвижения: 300, левыйБоковойВынос: -5),
      контурнаяМодель: КонтурыГлифа(контуры: [
        КонтурГлифа(
          идентификатор: ИдентификаторКонтура(1),
          точки: [ТочкаГлифа(идентификатор: ИдентификаторТочки(1), икс: 0, игрек: 0, наКривой: true)]
        )
      ])
    )
    var модель = try МодельРедактированияГлифов(глифы: [глиф], сопоставления: [])

    XCTAssertThrowsError(
      try модель.удалитьТочку(
        ИдентификаторТочки(1),
        изКонтура: ИдентификаторКонтура(1),
        глифа: глиф.идентификатор
      )
    ) {
      XCTAssertEqual($0 as? ОшибкаМоделиГлифа, .нельзяУдалитьПоследнююТочку)
    }
    XCTAssertEqual(модель.найтиГлиф(идентификатор: глиф.идентификатор)?
      .контурнаяМодель.контуры[0].точки.count, 1)
  }

  func test_ОтклоняетПовторныйИдентификаторТочки() {
    let глиф = Глиф(
      идентификатор: ИдентификаторГлифа(9),
      метрики: МетрикиГлифа(ширинаПродвижения: 300, левыйБоковойВынос: 0),
      контурнаяМодель: КонтурыГлифа(контуры: [
        КонтурГлифа(
          идентификатор: ИдентификаторКонтура(1),
          точки: [
            ТочкаГлифа(идентификатор: ИдентификаторТочки(1), икс: 0, игрек: 0, наКривой: true),
            ТочкаГлифа(идентификатор: ИдентификаторТочки(1), икс: 10, игрек: 10, наКривой: false),
          ]
        )
      ])
    )

    XCTAssertThrowsError(try МодельРедактированияГлифов(глифы: [глиф], сопоставления: [])) {
      XCTAssertEqual($0 as? ОшибкаМоделиГлифа, .повторныйИдентификаторТочки(ИдентификаторТочки(1)))
    }
  }

  func test_ОтклоняетНеизвестныеИдентификаторыИИндексВставки() throws {
    let глиф = try фикстура("глиф-простой-контур")
    var модель = try МодельРедактированияГлифов(глифы: [глиф], сопоставления: [])
    XCTAssertThrowsError(
      try модель.переместитьТочку(
        идентификаторГлифа: ИдентификаторГлифа(99),
        идентификаторТочки: ИдентификаторТочки(2),
        вИкс: 0,
        игрек: 0
      )
    ) {
      XCTAssertEqual($0 as? ОшибкаМоделиГлифа, .глифНеНайден(ИдентификаторГлифа(99)))
    }
    XCTAssertThrowsError(
      try модель.переместитьТочку(
        идентификаторГлифа: глиф.идентификатор,
        идентификаторТочки: ИдентификаторТочки(99),
        вИкс: 0,
        игрек: 0
      )
    ) {
      XCTAssertEqual($0 as? ОшибкаМоделиГлифа, .точкаНеНайдена(ИдентификаторТочки(99)))
    }
    XCTAssertThrowsError(
      try модель.вставитьТочку(
        ТочкаГлифа(идентификатор: ИдентификаторТочки(99), икс: 0, игрек: 0, наКривой: true),
        вКонтур: ИдентификаторКонтура(1),
        глифа: глиф.идентификатор,
        поИндексу: 99
      )
    ) {
      XCTAssertEqual($0 as? ОшибкаМоделиГлифа, .индексТочкиВнеГраниц)
    }
  }

  func test_КвадратичнаяКонтрольнаяТочкаСохраняетсяКакНеЛежащаяНаКривой() throws {
    let глиф = try фикстура("глиф-квадратичная-кривая")
    XCTAssertEqual(
      глиф.контурнаяМодель.контуры[0].точки.map(\.наКривой),
      [true, false, true]
    )
    XCTAssertEqual(глиф.контурнаяМодель.контуры[0].точки[1].идентификатор, ИдентификаторТочки(2))
  }

  private func фикстура(_ имя: String) throws -> Глиф {
    let адрес = try XCTUnwrap(
      Bundle.module.url(forResource: имя, withExtension: "json", subdirectory: "Фикстуры")
    )
    return try JSONDecoder().decode(Глиф.self, from: Data(contentsOf: адрес))
  }
}

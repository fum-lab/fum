#!/usr/bin/env python3
"""Восстановление 16 и 256 синтетических попыток отдельными процессами."""
import hashlib
import json
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import sys
import tempfile
import time


def потребовать(условие: bool, сообщение: str) -> None:
    if not условие: raise ValueError(сообщение)


def измерить(исполняемый: Path) -> tuple[int, dict]:
    итог = {'схема': 'fum.профили-восстановления.1', 'запуски': [],
            'исполняемыйШа256': hashlib.sha256(исполняемый.read_bytes()).hexdigest(),
            'исполнительШа256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    for количество in [16, 256]:
        корень = None
        процесс = None
        фаза = 'создать-каталог'
        try:
            корень = Path(tempfile.mkdtemp(prefix='fum-telegram-restart-')).resolve()
            (корень / 'журнал').mkdir(mode=0o700)
            with os.fdopen(os.open(корень / 'ключ', os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), 'wb') as файл:
                файл.write(secrets.token_bytes(32)); файл.flush(); os.fsync(файл.fileno())
            каталог = os.open(корень, os.O_RDONLY | os.O_DIRECTORY)
            try: os.fsync(каталог)
            finally: os.close(каталог)
            подготовка = None
            for фаза in ['подготовить', 'восстановить']:
                процесс = None
                начало = time.perf_counter_ns()
                процесс = subprocess.run([str(исполняемый), '--профиль-восстановления', фаза, '--каталог', str(корень),
                                         '--попыток', str(количество)], capture_output=True, text=True, timeout=45)
                длительность = time.perf_counter_ns() - начало
                if процесс.returncode != 0:
                    raise RuntimeError(f'Код процесса: {процесс.returncode}')
                результат = json.loads(процесс.stdout)
                потребовать(результат['схема'] == 'fum.профиль-восстановления.1' and результат['фаза'] == фаза, 'Схема либо фаза')
                потребовать(результат['попыток'] == количество and результат['записей'] == 4 * количество, 'Количество попыток и записей')
                потребовать(результат['проверено'] is True, 'Отсутствует подтверждение проверки')
                if фаза == 'подготовить':
                    подготовка = результат
                    потребовать(результат['отправлено'] == 2 + 3 * количество and результат['создано'] == 1 and результат['приёмов'] == 0, 'Транспорт подготовки')
                else:
                    потребовать(результат['процесс'] != подготовка['процесс'], 'Восстановление требует отдельного процесса')
                    потребовать(результат['создано'] == результат['отправлено'] == результат['приёмов'] == 0, 'Транспорт при восстановлении должен бездействовать')
                    потребовать(результат['фикстурыШа256'] == подготовка['фикстурыШа256'], 'Отпечаток фикстур')
                    потребовать(результат['сегментШа256'] == подготовка['сегментШа256'], 'Отпечаток сегмента')
                    потребовать(результат['сегментБайтов'] == подготовка['сегментБайтов'], 'Размер сегмента')
                    потребовать(результат['требуютРазбора'] == количество, 'Все незавершённые попытки требуют разбора')
                    потребовать(результат['восстановлениеСекунд'] > 0 and результат['процессорноеВремяСекунд'] >= 0, 'Время восстановления')
                    потребовать(результат['памятьДо']['текущая'] > 0 and результат['памятьПосле']['текущая'] > 0, 'Память восстановления')
                итог['запуски'].append({'попыток': количество, 'фаза': фаза, 'процессНаносекунд': длительность, 'результат': результат})
            shutil.rmtree(корень)
        except BaseException as ошибка:
            if корень is not None: print(f'Приватное незавершённое состояние: {корень}', file=sys.stderr)
            if процесс is not None:
                print(процесс.stdout, file=sys.stderr); print(процесс.stderr, file=sys.stderr)
            print(str(ошибка), file=sys.stderr)
            if isinstance(ошибка, subprocess.TimeoutExpired):
                print(ошибка.stdout, file=sys.stderr); print(ошибка.stderr, file=sys.stderr)
            итог.update(исход='неуспех', ошибка={'попыток': количество, 'фаза': фаза, 'тип': type(ошибка).__name__})
            return 2, итог
    итог['граница'] = 'Для каждого N два последовательных отдельных процесса по 45 секунд. Новый процесс не означает холодный дисковый кэш. Полное время процесса включает подготовку и проверки; внутренний интервал измеряет только открытие ядра.'
    return 0, итог


if __name__ == '__main__':
    потребовать(len(sys.argv) == 2, 'Требуется один путь исполняемого файла')
    исполняемый = Path(sys.argv[1])
    потребовать(исполняемый.is_absolute() and исполняемый.is_file(), 'Требуется абсолютный путь существующего файла')
    код, итог = измерить(исполняемый)
    print(json.dumps(итог, ensure_ascii=False, indent=2))
    raise SystemExit(код)

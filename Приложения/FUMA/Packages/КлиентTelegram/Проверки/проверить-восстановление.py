#!/usr/bin/env python3
"""Сквозная проверка аварийного хвоста двумя отдельными процессами без TDLib."""
import hashlib
import json
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import sys
import tempfile
import time
import unicodedata


def потребовать(условие: bool, сообщение: str) -> None:
    if not условие: raise ValueError(сообщение)


def проверить(исполняемый: Path) -> dict:
    корень = Path(tempfile.mkdtemp(prefix='fum-telegram-хвост-')).resolve()
    выводы = []
    try:
        (корень / 'журнал').mkdir(mode=0o700)
        ключ = os.open(корень / 'ключ', os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(ключ, 'wb') as файл:
            файл.write(secrets.token_bytes(32)); файл.flush(); os.fsync(файл.fileno())
        каталог = os.open(корень, os.O_RDONLY | os.O_DIRECTORY)
        try: os.fsync(каталог)
        finally: os.close(каталог)
        процессы = []
        for фаза in ['подготовить', 'восстановить']:
            начало = time.perf_counter_ns()
            процесс = subprocess.run([str(исполняемый), '--сквозной-хвост', фаза, '--каталог', str(корень)],
                                     capture_output=True, text=True, timeout=45)
            длительность = time.perf_counter_ns() - начало
            выводы.append(процесс)
            if процесс.returncode != 0:
                raise RuntimeError(f'Фаза {фаза}: код {процесс.returncode}')
            результат = json.loads(процесс.stdout)
            потребовать(результат['схема'] == 'fum.сквозной-хвост.1' and результат['фаза'] == фаза, 'Схема либо фаза хвоста')
            потребовать(результат['байтыСохранены'] is True, 'Точные байты хвоста не подтверждены')
            процессы.append({'фаза': фаза, 'процессНаносекунд': длительность, 'результат': результат})
        подготовка, восстановление = [процесс['результат'] for процесс in процессы]
        потребовать(подготовка['закрытие']['потокиЗавершены'] is True, 'Потоки не завершены')
        потребовать(подготовка['закрытие']['всеЗакрыты'] is False, 'Неожиданное Closed')
        потребовать(подготовка['закрытие']['требуетсяРазбор'] is True, 'Отсутствует требование разбора')
        потребовать(подготовка['закрытие']['неприменённыхКадров'] == 1, 'Количество кадров при закрытии')
        потребовать(подготовка['повторЗакрытияСовпадает'] is True, 'Повтор закрытия не совпал')
        потребовать(восстановление['разрывов'] == 1 and восстановление['неприменённыхКадров'] == 1, 'Количество записей хвоста')
        потребовать(восстановление['чужойКлючОтклонён'] is True and восстановление['разрывВхода'] is True, 'Чужой ключ либо разрыв входа')
        потребовать(восстановление['создано'] == восстановление['отправлено'] == восстановление['приёмов'] == 0, 'Транспорт восстановления')
        потребовать(восстановление['сообщений'] == 0 and восстановление['сегментНеИзменён'] is True, 'История либо сохранность сегмента')
        потребовать(подготовка['фикстураШа256'] == восстановление['фикстураШа256'], 'Отпечаток фикстуры')
        потребовать(подготовка['процесс'] != восстановление['процесс'], 'Восстановление требует отдельного процесса')
        сегмент = корень / 'журнал/сегмент.fumobs'
        сохранённые = сегмент.read_bytes()
        повтор = subprocess.run([str(исполняемый), '--сквозной-хвост', 'подготовить', '--каталог', str(корень)],
                                capture_output=True, text=True, timeout=45)
        выводы.append(повтор)
        потребовать(повтор.returncode == 2 and unicodedata.normalize('NFC', str(корень)) in unicodedata.normalize('NFC', повтор.stderr), 'Повторная подготовка либо путь отказа')
        потребовать(сегмент.read_bytes() == сохранённые, 'Сегмент изменён повторной подготовкой')
        пустой = корень / 'пустой'; пустой.mkdir(mode=0o700)
        (пустой / 'журнал').mkdir(mode=0o700)
        ключПустого = пустой / 'ключ'; ключПустого.write_bytes((корень / 'ключ').read_bytes()); ключПустого.chmod(0o600)
        отсутствует = subprocess.run([str(исполняемый), '--сквозной-хвост', 'восстановить', '--каталог', str(пустой)],
                                    capture_output=True, text=True, timeout=45)
        выводы.append(отсутствует)
        потребовать(отсутствует.returncode == 2 and unicodedata.normalize('NFC', str(пустой)) in unicodedata.normalize('NFC', отсутствует.stderr), 'Отказ отсутствующего сегмента либо путь')
        потребовать(not (пустой / 'журнал/сегмент.fumobs').exists(), 'Отказ создал сегмент')
        итог = {'схема': 'fum.сквозная-проверка-хвоста.1', 'процессы': процессы,
                'исполняемыйШа256': hashlib.sha256(исполняемый.read_bytes()).hexdigest(),
                'граница': 'Два содержательных процесса и два отказных запуска; новый процесс не означает холодный дисковый кэш.'}
        shutil.rmtree(корень)
        return итог
    except BaseException as ошибка:
        print(f'Приватное незавершённое состояние: {корень}', file=sys.stderr)
        for вывод in выводы:
            print(вывод.stdout, file=sys.stderr); print(вывод.stderr, file=sys.stderr)
        if isinstance(ошибка, subprocess.TimeoutExpired):
            print(ошибка.stdout, file=sys.stderr); print(ошибка.stderr, file=sys.stderr)
        raise


if __name__ == '__main__':
    потребовать(len(sys.argv) == 2, 'Требуется один путь исполняемого файла')
    исполняемый = Path(sys.argv[1])
    потребовать(исполняемый.is_absolute() and исполняемый.is_file(), 'Требуется абсолютный путь существующего файла')
    print(json.dumps(проверить(исполняемый), ensure_ascii=False, indent=2))

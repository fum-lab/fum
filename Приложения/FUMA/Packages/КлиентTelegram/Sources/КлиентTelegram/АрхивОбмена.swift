public enum НаправлениеОбмена: String, Codable, Sendable { case исходящееНамерение, входящиеБайты }

public struct ЗаписьОбмена: Codable, Equatable, Sendable {
    public let версия: Int
    public let порядок: Int
    public let поколение: UUID
    public let вид: String
    public let привязка: String
    public let библиотека: ПривязкаБиблиотеки?
    public let направление: НаправлениеОбмена?
    public let клиент: Int32?
    public let байты: Data?
    public let разрыв: String?
}

private final class ФактНачальнойЗаписи: @unchecked Sendable {
    private let замок = NSLock()
    private var записано = false
    func отметить() { замок.withLock { записано = true } }
    var естьЗапись: Bool { замок.withLock { записано } }
}

/// Единственный сериализованный владелец отдельного сегмента AES-256-GCM.
/// Ключ хранится отдельно. Видимыми остаются случайные ID, размеры и число записей.
/// Прочтение и открытие нового поколения никогда не вызывают транспорт/replay-send.
public final class АрхивОбмена: @unchecked Sendable {
    private let замок = NSLock()
    private let контейнер: Сегмент
    private let ключ: SymmetricKey
    private let корень: URL
    private let родитель: URL
    private let идентичность: ИдентичностьКаталога
    private let идентичностьРодителя: ИдентичностьКаталога
    private let привязка: ПривязкаБиблиотеки
    private let привязкаИД: String
    private let запись: Bool
    private let наблюдать: (@Sendable (String, UInt64) -> Void)?
    private var поколение = UUID()
    private var порядок = 0
    private var отказ = false
    private var поколениеЗакрыто = false

    init(корень: URL, ключ: Data, привязка: ПривязкаБиблиотеки, запись: Bool = true,
         операции: ФайловыеОперации = .системные, наблюдать: (@Sendable (String, UInt64) -> Void)? = nil,
         передОткрытиемСегмента: (() throws -> Void)? = nil) throws {
        guard ключ.count == 32 else { throw ОшибкаКлиента.неверныеДанные("256-битный ключ архива обмена") }
        self.ключ = SymmetricKey(data: ключ); self.привязка = привязка
        привязкаИД = привязка.идентификатор; self.запись = запись; self.наблюдать = наблюдать
        родитель = корень
        идентичностьРодителя = try идентичностьПриватногоКаталога(корень)
        self.корень = корень.appendingPathComponent("обмен", isDirectory: true)
        if запись {
            try сПриватнымКаталогом(корень) { файл, _ in
                if mkdirat(файл, "обмен", 0o700) != 0, errno != EEXIST { throw ОшибкаКлиента.доступЗапрещён("Каталог архива недоступен") }
                // EEXIST может быть следствием прежнего mkdir с неизвестным fsync.
                try операции.синхронизация(файл)
            }
        }
        идентичность = try идентичностьПриватногоКаталога(self.корень)
        try проверитьПриватностьСегмента(корень: self.корень, отсутствиеРазрешено: запись)
        try передОткрытиемСегмента?()
        let факт = ФактНачальнойЗаписи()
        let наблюдаемыеОперации = ФайловыеОперации(запись: { дескриптор, буфер in
            let число = try операции.запись(дескриптор, буфер)
            if число > 0 { факт.отметить() }
            return число
        }, синхронизация: операции.синхронизация)
        контейнер = try Сегмент(кореньДанных: self.корень, запись: запись, создать: запись, операции: наблюдаемыеОперации)
        // Текущий Сегмент.init пишет только сигнатуру нового файла после O_EXCL
        // и под EX flock; существующий файл лишь сканирует. Успешный возврат
        // подтверждает полную запись и fsync. Факт фиксируется до наших записей.
        let сегментСоздан = факт.естьЗапись
        do {
            guard !контейнер.естьХвост else { throw ОшибкаКлиента.требуетсяРазбор }
            let прежние = try прочитатьПодЗамком()
            guard !прежние.isEmpty || (запись && сегментСоздан) else { throw ОшибкаКлиента.требуетсяРазбор }
            порядок = прежние.count
            if запись {
                if прежние.isEmpty { try добавитьПодЗамком(вид: "привязка", библиотека: привязка) }
                поколение = UUID()
                try добавитьПодЗамком(вид: "поколение")
            }
        } catch { контейнер.закрыть(); throw error }
    }

    private func приватность() throws {
        guard try идентичностьПриватногоКаталога(родитель) == идентичностьРодителя,
              try идентичностьПриватногоКаталога(корень) == идентичность else { throw ОшибкаКлиента.доступЗапрещён("Каталог архива был заменён") }
        try проверитьПриватностьСегмента(корень: корень)
    }

    private func прочитатьПодЗамком() throws -> [ЗаписьОбмена] {
        try приватность()
        var результат: [ЗаписьОбмена] = [], текущее: UUID?, закрыто = false
        for квитанция in контейнер.записи {
            guard квитанция.описание.тип == "телеграм/сырой-зашифрованный-обмен", квитанция.описание.версияСхемы == 1,
                  квитанция.размер <= 32 * 1024 * 1024 else { throw ОшибкаКлиента.требуетсяРазбор }
            let открыто = try AES.GCM.open(AES.GCM.SealedBox(combined: контейнер.извлечь(квитанция.описание.идентификатор)),
                using: ключ, authenticating: Data(квитанция.описание.идентификатор.utf8))
            let запись = try JSONDecoder().decode(ЗаписьОбмена.self, from: открыто)
            guard запись.версия == 1, запись.порядок == результат.count, запись.привязка == привязкаИД else { throw ОшибкаКлиента.требуетсяРазбор }
            switch запись.вид {
            case "привязка":
                guard результат.isEmpty, запись.библиотека == привязка, запись.байты == nil, запись.направление == nil, запись.клиент == nil, запись.разрыв == nil else { throw ОшибкаКлиента.требуетсяРазбор }
            case "поколение":
                guard !результат.isEmpty, запись.библиотека == nil, запись.байты == nil, запись.направление == nil, запись.клиент == nil,
                      запись.разрыв == nil, !результат.contains(where: { $0.вид == "поколение" && $0.поколение == запись.поколение }) else { throw ОшибкаКлиента.требуетсяРазбор }
                текущее = запись.поколение; закрыто = false
            case "кадр":
                guard запись.поколение == текущее, !закрыто, запись.библиотека == nil, запись.байты != nil, запись.направление != nil, запись.разрыв == nil,
                      (запись.направление == .входящиеБайты && запись.клиент == nil) || (запись.направление == .исходящееНамерение && (запись.клиент ?? 0) > 0) else { throw ОшибкаКлиента.требуетсяРазбор }
            case "конец":
                guard запись.поколение == текущее, !закрыто, запись.библиотека == nil, запись.байты == nil, запись.направление == nil, запись.клиент == nil, запись.разрыв == nil else { throw ОшибкаКлиента.требуетсяРазбор }
                закрыто = true
            case "разрыв":
                guard запись.поколение == текущее, !закрыто, запись.библиотека == nil, запись.байты == nil, запись.направление == nil, запись.клиент == nil,
                      !(запись.разрыв ?? "").isEmpty else { throw ОшибкаКлиента.требуетсяРазбор }
            default: throw ОшибкаКлиента.требуетсяРазбор
            }
            результат.append(запись)
        }
        try приватность()
        return результат
    }

    public func снимок() throws -> [ЗаписьОбмена] {
        try замок.withLock { guard !отказ else { throw ОшибкаКлиента.требуетсяРазбор }; return try прочитатьПодЗамком() }
    }

    public static func прочитать(корень: URL, ключ: Data, привязка: ПривязкаБиблиотеки) throws -> [ЗаписьОбмена] {
        let архив = try АрхивОбмена(корень: корень, ключ: ключ, привязка: привязка, запись: false)
        defer { архив.закрыть() }
        return try архив.снимок()
    }

    func сохранить(_ байты: Data, направление: НаправлениеОбмена, клиент: Int32? = nil) throws {
        try замок.withLock { try добавитьПодЗамком(вид: "кадр", направление: направление, клиент: клиент, байты: байты) }
    }
    func сохранитьРазрыв(_ основание: String) throws { try замок.withLock { try добавитьПодЗамком(вид: "разрыв", разрыв: основание) } }

    private func добавитьПодЗамком(вид: String, библиотека: ПривязкаБиблиотеки? = nil,
                                  направление: НаправлениеОбмена? = nil, клиент: Int32? = nil, байты: Data? = nil, разрыв: String? = nil) throws {
        guard запись, !отказ, !поколениеЗакрыто else { throw ОшибкаКлиента.требуетсяРазбор }
        do {
            try приватность()
            let запись = ЗаписьОбмена(версия: 1, порядок: порядок, поколение: поколение, вид: вид,
                привязка: привязкаИД, библиотека: библиотека, направление: направление, клиент: клиент, байты: байты, разрыв: разрыв)
            let данные = try кодироватьЛокально(запись)
            guard данные.count <= 24 * 1024 * 1024 else { throw ОшибкаКлиента.превышенПредел }
            let идентификатор = UUID().uuidString
            let началоШифрования = DispatchTime.now().uptimeNanoseconds
            let закрыто = try AES.GCM.seal(данные, using: ключ, authenticating: Data(идентификатор.utf8))
            наблюдать?("шифрование", DispatchTime.now().uptimeNanoseconds - началоШифрования)
            guard let шифротекст = закрыто.combined else { throw ОшибкаКлиента.требуетсяРазбор }
            _ = try контейнер.добавить(ОписаниеНаблюдения(идентификатор: идентификатор,
                тип: "телеграм/сырой-зашифрованный-обмен", источник: "локальный-клиент", время: "порядок-архива",
                спецификация: Data("fum.сырой-обмен.1; AES-256-GCM".utf8)), данные: шифротекст)
            try приватность()
            порядок += 1
            if вид == "конец" { поколениеЗакрыто = true }
        } catch { отказ = true; throw error }
    }

    func закончитьПоколение() throws { try замок.withLock { try добавитьПодЗамком(вид: "конец") } }
    public func закрыть() { замок.withLock { контейнер.закрыть(); отказ = true } }
    deinit { контейнер.закрыть() }
}

/// Archive lock не охватывает блокирующий receive. После отказа входящая запись
/// не возвращается очереди/парсеру; ЦиклПриёма останавливается на брошенной ошибке.
final class АрхивирующийТранспорт: ТранспортБиблиотеки, @unchecked Sendable {
    let базовый: any ТранспортБиблиотеки
    let архив: АрхивОбмена
    private let отправка = NSLock()
    init(_ базовый: any ТранспортБиблиотеки, архив: АрхивОбмена) { self.базовый = базовый; self.архив = архив }
    func создатьКлиента() -> Int32 { базовый.создатьКлиента() }
    func отправить(клиент: Int32, запрос: Data) throws {
        guard клиент > 0, !запрос.contains(0), String(data: запрос, encoding: .utf8) != nil else { throw ОшибкаКлиента.неверныеДанные("UTF-8 запрос без NUL") }
        try отправка.withLock {
            try архив.сохранить(запрос, направление: .исходящееНамерение, клиент: клиент)
            try базовый.отправить(клиент: клиент, запрос: запрос)
        }
    }
    func принять(таймАут: Double) throws -> Data? {
        let принятые: Data?
        do { принятые = try базовый.принять(таймАут: таймАут) }
        catch {
            let основание = (error as? ОшибкаКлиента) == .превышенПредел
                ? "Ответ C не скопирован из-за предела; точные байты неизвестны"
                : "Нижний receive завершился ошибкой до возврата Data; точные байты неизвестны"
            try архив.сохранитьРазрыв(основание)
            throw error
        }
        guard let байты = принятые else { return nil }
        try архив.сохранить(байты, направление: .входящиеБайты)
        return байты
    }
}

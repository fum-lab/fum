private final class ОбработчикОтменыПрофиля: @unchecked Sendable {
    private let замок = NSLock()
    private var отменён = false
    private var продолжение: CheckedContinuation<Void, Error>?
    private var начато = 0
    let готов = БарьерПрофиля()
    let допускТранспорта = БарьерПрофиля()
    var числоНачатых: Int { замок.withLock { начато } }
    func ждатьОтмены() async throws {
        try await withTaskCancellationHandler {
            try await withCheckedThrowingContinuation { новое in
                let сразу = замок.withLock {
                    начато += 1
                    if отменён { return true }
                    продолжение = новое
                    return false
                }
                готов.открыть()
                if сразу { новое.resume(throwing: CancellationError()) }
            }
        } onCancel: { self.отменить() }
    }
    func отменить() {
        let ожидающее = замок.withLock {
            отменён = true
            let результат = продолжение; продолжение = nil
            return результат
        }
        // Ни синхронный транспорт, ни continuation не вызываются под собственным замком.
        допускТранспорта.открыть()
        ожидающее?.resume(throwing: CancellationError())
    }
}

private final class ТранспортОтменыПрофиля: ТранспортБиблиотеки, @unchecked Sendable {
    private let замок = NSLock()

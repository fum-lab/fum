private final class БарьерПрофиля: @unchecked Sendable {
    private let условие = NSCondition()
    private var открыт = false
    private var ожидающие: [UUID: CheckedContinuation<Bool, Never>] = [:]
    func открыть() {
        let продолжения = условие.withLock {
            открыт = true
            let все = Array(ожидающие.values); ожидающие.removeAll()
            условие.broadcast(); return все
        }
        for продолжение in продолжения { продолжение.resume(returning: true) }
    }
    func ждать() async throws {
        let принято = await withCheckedContinuation { продолжение in
            let номер = UUID()
            let сразу = условие.withLock {
                if открыт { return true }
                ожидающие[номер] = продолжение; return false
            }
            if сразу { продолжение.resume(returning: true) }
            else {
                DispatchQueue.global().asyncAfter(deadline: .now() + 15) { [weak self] in
                    guard let self else { return }
                    let просроченное = условие.withLock { ожидающие.removeValue(forKey: номер) }
                    просроченное?.resume(returning: false)
                }
            }
        }
        guard принято else { throw ОшибкаКлиента.требуетсяРазбор }
    }
    func ждатьВПотоке() throws {
        условие.lock(); defer { условие.unlock() }
        let край = Date(timeIntervalSinceNow: 15)
        while !открыт {
            guard условие.wait(until: край) || открыт else { throw ОшибкаКлиента.требуетсяРазбор }
        }
    }
}

private struct ПамятьПрофиля: Encodable {
    let текущая: UInt64
    let пикПроцесса: UInt64
    init() throws {
        var сведения = mach_task_basic_info_data_t()
        let ёмкость = MemoryLayout<mach_task_basic_info_data_t>.size / MemoryLayout<integer_t>.size
        var количество = mach_msg_type_number_t(ёмкость)
        let исход = withUnsafeMutablePointer(to: &сведения) { указатель in
            указатель.withMemoryRebound(to: integer_t.self, capacity: ёмкость) {
                task_info(mach_task_self_, task_flavor_t(MACH_TASK_BASIC_INFO), $0, &количество)
            }
        }
        guard исход == KERN_SUCCESS, количество == ёмкость else { throw ОшибкаКлиента.требуетсяРазбор }
        текущая = сведения.resident_size; пикПроцесса = сведения.resident_size_max
    }
}

private func процессорПрофиля() throws -> Double {
    var сведения = rusage()
    guard getrusage(RUSAGE_SELF, &сведения) == 0 else { throw ОшибкаКлиента.требуетсяРазбор }
    return Double(сведения.ru_utime.tv_sec + сведения.ru_stime.tv_sec)
        + Double(сведения.ru_utime.tv_usec + сведения.ru_stime.tv_usec) / 1_000_000
}


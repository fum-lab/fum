private final class ТранспортПотокаПрофиля: ТранспортБиблиотеки, @unchecked Sendable {
    private let замок = NSLock()
    private var следующийКлиент: Int32 = 1
    private var последний: ЗначениеДанных?
    private var номер = 0
    private var времена: [UInt64] = []
    private var хэш = SHA256()
    let измеряемых: Int
    let допуск = БарьерПрофиля()
    init(измеряемых: Int) { self.измеряемых = измеряемых; времена.reserveCapacity(измеряемых + 32) }
    func создатьКлиента() -> Int32 { замок.withLock { defer { следующийКлиент += 1 }; return следующийКлиент } }
    func отправить(клиент: Int32, запрос: Data) throws {
        let данные = try ЗначениеДанных.прочитать(запрос)
        замок.withLock { последний = данные }
    }
    var последнийЗапрос: ЗначениеДанных? { замок.withLock { последний } }
    var получено: Int { замок.withLock { времена.count } }
    var хэшФикстур: String { замок.withLock { хэш.finalize().map { String(format: "%02x", $0) }.joined() } }
    func началоКопирования(_ индекс: Int) throws -> UInt64 {
        try замок.withLock {
            guard времена.indices.contains(индекс) else { throw ОшибкаКлиента.требуетсяРазбор }
            return времена[индекс]
        }
    }
    func принять(таймАут: Double) throws -> Data? {
        let индекс = замок.withLock { let текущий = номер; номер += 1; return текущий }
        guard индекс < 32 + измеряемых else { Thread.sleep(forTimeInterval: таймАут); return nil }
        if индекс == 32 { try допуск.ждатьВПотоке() }
        let поля: [String: ЗначениеДанных] = ["id": .число(Int64(индекс + 1) * 1048576), "chat_id": .число(-100001), "sending_state": .пусто]
        func кадр(_ текст: String) -> ЗначениеДанных {
            var сообщение = поля
            сообщение["content"] = .типа("messageText", ["text": .типа("formattedText", ["text": .текст(текст), "entities": .массив([])])])
            return .типа("updateNewMessage", ["@client_id": .число(Int64(индекс % 2 + 1)), "message": .типа("message", сообщение)])
        }
        let размерОснования = try кадр("").байты().count
        guard размерОснования < 4096 else { throw ОшибкаКлиента.превышенПредел }
        var данные = try кадр(String(repeating: "x", count: 4096 - размерОснования)).байты()
        guard данные.count == 4096 else { throw ОшибкаКлиента.требуетсяРазбор }
        замок.withLock { хэш.update(data: данные) }
        данные.append(0)
        замок.withLock { времена.append(DispatchTime.now().uptimeNanoseconds) }
        return try данные.withUnsafeBytes { указатель in
            try скопироватьОтвет(указатель.bindMemory(to: CChar.self).baseAddress!, предел: 4096)
        }
    }
}

private actor ПолучательПрофиля {
    let ядро: ЯдроКлиента
    let транспорт: ТранспортПотокаПрофиля
    let прогрет = БарьерПрофиля()
    let завершён = БарьерПрофиля()
    var применено = 0
    var полученоБайтов = 0
    private var хэш = SHA256()
    var полученныеШа256: String { хэш.finalize().map { String(format: "%02x", $0) }.joined() }
    var передача: [UInt64] = []
    var обработка: [UInt64] = []
    init(ядро: ЯдроКлиента, транспорт: ТранспортПотокаПрофиля) {
        self.ядро = ядро; self.транспорт = транспорт
        передача.reserveCapacity(транспорт.измеряемых); обработка.reserveCapacity(транспорт.измеряемых)
    }
    func принять(_ данные: Data) async throws {
        let начало = DispatchTime.now().uptimeNanoseconds
        try await ядро.принять(данные)
        let конец = DispatchTime.now().uptimeNanoseconds
        хэш.update(data: данные)
        полученоБайтов += данные.count
        if применено >= 32 {
            guard передача.count < транспорт.измеряемых else { throw ОшибкаКлиента.превышенПредел }
            передача.append(начало - (try транспорт.началоКопирования(применено)))
            обработка.append(конец - начало)
        }
        применено += 1
        if применено == 32 { прогрет.открыть() }
        if применено == 32 + транспорт.измеряемых { завершён.открыть() }
    }
}


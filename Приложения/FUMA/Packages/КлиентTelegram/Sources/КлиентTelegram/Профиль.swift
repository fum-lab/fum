package func измеритьСинтетическуюОтмену(количество: Int) async throws -> Data {
    guard (1...100).contains(количество) else { throw ОшибкаКлиента.неверныеДанные("Профиль: 1–100 отмен") }
    var измерения: [UInt64] = []; измерения.reserveCapacity(количество)
    var процессорноеВремя = 0.0
    var памятьДо: ПамятьПрофиля?
    var хэшПовтора = ""
    for повтор in 0..<(количество + 5) {
        if повтор == 5 { памятьДо = try ПамятьПрофиля() }
        let обработчик = ОбработчикОтменыПрофиля()
        let транспорт = ТранспортОтменыПрофиля(обработчик)
        let цикл = try ЦиклПриёма(транспорт: транспорт, ёмкость: 2, пределБайтов: 8192) { _ in
            try await обработчик.ждатьОтмены()
        }
        do {
            try цикл.запустить()
            try await обработчик.готов.ждать()
            try await транспорт.четвёртыйСкопирован.ждать()
            guard цикл.пикКоличество == 2, цикл.пикБайтов == 8192 else { throw ОшибкаКлиента.требуетсяРазбор }
            let процессорДо = try процессорПрофиля()
            let начало = DispatchTime.now().uptimeNanoseconds
            await цикл.остановить(отменитьОбработку: true)
            let конец = DispatchTime.now().uptimeNanoseconds
            let процессорПосле = try процессорПрофиля()
            guard транспорт.получено == 4, обработчик.числоНачатых == 1,
                  цикл.причинаОстановки == .требуетсяРазбор, цикл.незавершённые == транспорт.кадры else {
                throw ОшибкаКлиента.требуетсяРазбор
            }
            if повтор >= 5 {
                измерения.append(конец - начало)
                процессорноеВремя += процессорПосле - процессорДо

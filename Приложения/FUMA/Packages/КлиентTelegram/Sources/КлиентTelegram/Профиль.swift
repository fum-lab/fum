    let кадры = (1...4).map { Data(repeating: UInt8($0), count: 4096) }
    let четвёртыйСкопирован = БарьерПрофиля()
    let обработчик: ОбработчикОтменыПрофиля
    init(_ обработчик: ОбработчикОтменыПрофиля) { self.обработчик = обработчик }
    var получено: Int { замок.withLock { номер } }
    func создатьКлиента() -> Int32 { 1 }
    func отправить(клиент: Int32, запрос: Data) throws { throw ОшибкаКлиента.требуетсяРазбор }
    func принять(таймАут: Double) throws -> Data? {
        let индекс = замок.withLock { let текущий = номер; номер += 1; return текущий }
        guard индекс < кадры.count else { throw ОшибкаКлиента.требуетсяРазбор }
        var буфер = кадры[индекс]; буфер.append(0)
        let копия = try буфер.withUnsafeBytes {
            try скопироватьОтвет($0.bindMemory(to: CChar.self).baseAddress!, предел: 4096)
        }
        if индекс == 3 {
            четвёртыйСкопирован.открыть()
            try обработчик.допускТранспорта.ждатьВПотоке()
        }
        return копия
    }
}


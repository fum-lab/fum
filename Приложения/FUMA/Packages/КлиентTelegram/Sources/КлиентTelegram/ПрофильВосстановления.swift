/// Ограниченное чтение обычного приватного файла. Проверка метаданных может не читать его содержимое.
private func сФайломПрофиля<Результат>(_ корень: URL, имя: String, предел: Int,
                                      действие: (Int32, Int) throws -> Результат) throws -> Результат {
    try сПриватнымКаталогом(корень) { каталог, _ in
        let файл = openat(каталог, имя, O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC)
        guard файл >= 0 else { throw ОшибкаКлиента.требуетсяРазбор }
        defer { Darwin.close(файл) }
        var до = stat()
        guard fstat(файл, &до) == 0, до.st_mode & S_IFMT == S_IFREG, до.st_uid == geteuid(),
              до.st_mode & 0o7777 == 0o600, до.st_nlink == 1, до.st_size > 0, до.st_size <= предел else {
            throw ОшибкаКлиента.требуетсяРазбор
        }
        try проверитьОтсутствиеРасширенногоДоступа(файл)
        let результат = try действие(файл, Int(до.st_size))
        var после = stat(), имяПосле = stat()
        guard fstat(файл, &после) == 0, fstatat(каталог, имя, &имяПосле, AT_SYMLINK_NOFOLLOW) == 0,
              до.st_size == после.st_size, до.st_mtimespec.tv_sec == после.st_mtimespec.tv_sec,
              до.st_mtimespec.tv_nsec == после.st_mtimespec.tv_nsec, до.st_ctimespec.tv_sec == после.st_ctimespec.tv_sec,
              до.st_ctimespec.tv_nsec == после.st_ctimespec.tv_nsec,
              имяПосле.st_dev == после.st_dev, имяПосле.st_ino == после.st_ino else { throw ОшибкаКлиента.требуетсяРазбор }
        return результат
    }
}
private func прочитатьФайлПрофиля(_ корень: URL, имя: String, предел: Int) throws -> Data {
    try сФайломПрофиля(корень, имя: имя, предел: предел) { файл, размер in
        var данные = Data(count: размер)
        try данные.withUnsafeMutableBytes { байты in
            var смещение = 0
            while смещение < размер {
                let число = pread(файл, байты.baseAddress!.advanced(by: смещение), размер - смещение, off_t(смещение))
                if число < 0, errno == EINTR { continue }
                guard число > 0 else { throw ОшибкаКлиента.требуетсяРазбор }
                смещение += число
            }
        }
        return данные
    }
}
private func записатьКвитанциюВосстановления(_ квитанция: КвитанцияВосстановления, корень: URL) throws {
    let данные = try кодироватьЛокально(квитанция)
    guard данные.count <= 262144 else { throw ОшибкаКлиента.превышенПредел }
    try сПриватнымКаталогом(корень) { каталог, _ in
        let файл = openat(каталог, "квитанция.json", O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        guard файл >= 0 else { throw ОшибкаКлиента.требуетсяРазбор }
        defer { Darwin.close(файл) }
        try данные.withUnsafeBytes { байты in
            var смещение = 0
            while смещение < байты.count {
                let число = Darwin.write(файл, байты.baseAddress!.advanced(by: смещение), байты.count - смещение)
                if число < 0, errno == EINTR { continue }
                guard число > 0 else { throw ОшибкаКлиента.требуетсяРазбор }
                смещение += число
            }
        }
        guard fsync(файл) == 0, fsync(каталог) == 0 else { throw ОшибкаКлиента.требуетсяРазбор }
    }
}

private func подготовитьВосстановление(каталог: URL, корень: URL, ключ: Data, количество: Int) async throws -> Data {
    guard try FileManager.default.contentsOfDirectory(atPath: корень.path).isEmpty else {
        throw ОшибкаКлиента.неверныеДанные("Подготовке нужен пустой журнал")
    }
    let транспорт = ТранспортПрофиляВосстановления(разрешён: true)
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: корень, ключ: ключ)
    do {
        _ = try await ядро.добавитьКлиента(аккаунт: 17)
        try await ответитьВПрофиле(.типа("authorizationStateReady"), на: "getAuthorizationState", ядро: ядро, транспорт: транспорт)
        try await ответитьВПрофиле(.типа("user", ["id": .число(17)]), на: "getMe", ядро: ядро, транспорт: транспорт)
        var связи: [СвязьВосстановления] = []
        var фикстуры = SHA256()
        for номер in 1...количество {
            let черновик = try черновикВосстановления(номер)
            фикстуры.update(data: try кодироватьЛокально(черновик))
            try await ядро.сохранитьЧерновик(черновик)
            let разрешение = try РазрешениеДействия(черновик: черновик, основание: основаниеВосстановления)
            let идентификатор = try await ядро.выполнить(1, черновик: черновик.идентификатор, разрешение: разрешение)
            try await ответитьВПрофиле(.типа("chat", ["id": .число(-100001),
                "type": .типа("chatTypeSupergroup", ["supergroup_id": .число(51), "is_channel": .флаг(true)])]),
                на: "getChat", ядро: ядро, транспорт: транспорт)
            try await ответитьВПрофиле(.типа("supergroup", ["id": .число(51), "is_channel": .флаг(true),
                "status": .типа("chatMemberStatusAdministrator", ["rights": .типа("chatAdministratorRights", ["can_post_messages": .флаг(true)])])]),
                на: "getSupergroup", ядро: ядро, транспорт: транспорт)
            guard case .текст(let текст) = черновик.действие else { throw ОшибкаКлиента.требуетсяРазбор }
            let наблюдение = try await ответитьВПрофиле(.типа("message", ["id": .число(Int64(100000 + номер)), "chat_id": .число(-100001),
                "content": .типа("messageText", ["text": .типа("formattedText", ["text": .текст(текст), "entities": .массив([])])]),
                "sending_state": .типа("messageSendingStatePending", ["sending_id": .число(Int64(номер))])]),
                на: "sendMessage", ядро: ядро, транспорт: транспорт)
            guard let попытка = await ядро.получитьПопытки().first(where: { $0.идентификатор == идентификатор }),
                  попытка.состояние == .ожидает, попытка.сообщения == [ИсходСообщения(временный: Int64(100000 + номер))],
                  попытка.запрос["@extra"] == nil, await ядро.ожидаемые.isEmpty, await ядро.подготовки.isEmpty else {
                throw ОшибкаКлиента.требуетсяРазбор
            }
            связи.append(СвязьВосстановления(номер: номер, попытка: идентификатор,
                запросШа256: отпечаток(try попытка.запрос.байты()), событиеШа256: отпечаток(try наблюдение.байты())))
        }
        await ядро.закрытьЖурнал()
        let журнал = try ЛокальныйЖурнал(корень: корень, ключ: ключ)
        let записей: Int
        do { записей = try журнал.восстановить().count; журнал.закрыть() }
        catch { журнал.закрыть(); throw error }
        let сегмент = try прочитатьФайлПрофиля(корень, имя: "сегмент.fumobs", предел: 16 * 1024 * 1024)
        let квитанция = КвитанцияВосстановления(версия: 2, количество: количество, записей: записей,
            сегментБайтов: сегмент.count, сегментШа256: отпечаток(сегмент),
            фикстурыШа256: фикстуры.finalize().map { String(format: "%02x", $0) }.joined(), связи: связи)
        guard записей == 4 * количество, транспорт.счётчики == (1, 2 + 3 * количество, 0) else { throw ОшибкаКлиента.требуетсяРазбор }
        try записатьКвитанциюВосстановления(квитанция, корень: каталог)
        return try кодироватьЛокально(РезультатВосстановления(фаза: "подготовить", попыток: количество, записей: записей,
            сегментБайтов: сегмент.count, сегментШа256: квитанция.сегментШа256, фикстурыШа256: квитанция.фикстурыШа256,
            проверено: true, создано: 1, отправлено: 2 + 3 * количество, приёмов: 0))
    } catch { await ядро.закрытьЖурнал(); throw error }
}

package func измеритьВосстановление(каталог: URL, количество: Int, подготовка: Bool) async throws -> Data {
    guard [16, 256].contains(количество) else { throw ОшибкаКлиента.неверныеДанные("Профиль восстановления: 16 либо 256 попыток") }
    let ключ = try прочитатьПриватныйКлюч(каталог: каталог, имяФайла: "ключ")
    let корень = каталог.appendingPathComponent("журнал", isDirectory: true)
    _ = try идентичностьПриватногоКаталога(корень)
    if подготовка { return try await подготовитьВосстановление(каталог: каталог, корень: корень, ключ: ключ, количество: количество) }
    // Только метаданные до интервала; сегмент и квитанция не читаются ради проверки ожидаемого результата заранее.
    let размер = try сФайломПрофиля(корень, имя: "сегмент.fumobs", предел: 16 * 1024 * 1024) { _, размер in размер }
    _ = try сФайломПрофиля(каталог, имя: "квитанция.json", предел: 262144) { _, размер in размер }
    let транспорт = ТранспортПрофиляВосстановления(разрешён: false)
    let памятьДо = try ПамятьПрофиля(), процессорДо = try процессорПрофиля()
    let начало = ContinuousClock.now
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: корень, ключ: ключ)
    let интервал = (ContinuousClock.now - начало).components
    do {
        let процессор = try процессорПрофиля() - процессорДо
        let памятьПосле = try ПамятьПрофиля()
        let квитанция = try JSONDecoder().decode(КвитанцияВосстановления.self,
            from: прочитатьФайлПрофиля(каталог, имя: "квитанция.json", предел: 262144))
        guard квитанция.версия == 2, квитанция.количество == количество, квитанция.записей == 4 * количество,
              квитанция.сегментБайтов == размер, квитанция.связи.count == количество,
              Set(квитанция.связи.map(\.номер)) == Set(1...количество), Set(квитанция.связи.map(\.попытка)).count == количество else {
            throw ОшибкаКлиента.требуетсяРазбор
        }
        let попытки = await ядро.получитьПопытки()
        let модель = await ядро.получитьМодельСообщений()
        guard попытки.count == количество, await ядро.черновики.count == количество,
              модель.история.count == количество, модель.сообщения.count == количество,
              await ядро.клиенты.isEmpty, await ядро.ожидаемые.isEmpty, await ядро.подготовки.isEmpty,
              !(await ядро.разрывВхода), транспорт.счётчики == (0, 0, 0) else { throw ОшибкаКлиента.требуетсяРазбор }
        var фикстуры = SHA256()
        for связь in квитанция.связи.sorted(by: { $0.номер < $1.номер }) {
            let черновик = try черновикВосстановления(связь.номер)
            фикстуры.update(data: try кодироватьЛокально(черновик))
            let разрешение = try РазрешениеДействия(черновик: черновик, основание: основаниеВосстановления)
            guard let попытка = попытки.first(where: { $0.идентификатор == связь.попытка }),
                  попытка.черновик == черновик, попытка.разрешение == разрешение,
                  try await ядро.предпросмотр(черновик.идентификатор) == черновик,
                  попытка.состояние == .требуетсяРазбор, попытка.кодОшибки == nil, !попытка.противоречие,
                  попытка.сообщения == [ИсходСообщения(временный: Int64(100000 + связь.номер))],
                  отпечаток(try попытка.запрос.байты()) == связь.запросШа256, попытка.запрос["@extra"] == nil else {
                throw ОшибкаКлиента.требуетсяРазбор
            }
            let наблюдение = модель.история[связь.номер - 1]
            let номер = Int64(100000 + связь.номер)
            guard наблюдение.порядок == связь.номер, наблюдение.аккаунт == 17,
                  отпечаток(try наблюдение.событие.байты()) == связь.событиеШа256,
                  наблюдение.событие["id"]?.целое == номер, наблюдение.событие["chat_id"]?.целое == -100001,
                  наблюдение.событие["sending_state"]?.тип == "messageSendingStatePending",
                  let снимок = модель.сообщения[ИдентичностьСообщения(аккаунт: 17, чат: -100001, сообщение: номер)],
                  снимок.данные == наблюдение.событие, !снимок.удалено, !снимок.очищенКэш else { throw ОшибкаКлиента.требуетсяРазбор }
        }
        let хэшФикстур = фикстуры.finalize().map { String(format: "%02x", $0) }.joined()
        guard хэшФикстур == квитанция.фикстурыШа256 else { throw ОшибкаКлиента.требуетсяРазбор }
        await ядро.закрытьЖурнал()
        let сегмент = try прочитатьФайлПрофиля(корень, имя: "сегмент.fumobs", предел: 16 * 1024 * 1024)
        guard сегмент.count == размер, отпечаток(сегмент) == квитанция.сегментШа256 else { throw ОшибкаКлиента.требуетсяРазбор }
        return try кодироватьЛокально(РезультатВосстановления(фаза: "восстановить", попыток: количество,
            записей: квитанция.записей, сегментБайтов: размер, сегментШа256: квитанция.сегментШа256,
            фикстурыШа256: хэшФикстур, проверено: true, создано: 0, отправлено: 0, приёмов: 0, требуютРазбора: количество,
            восстановлениеСекунд: Double(интервал.seconds) + Double(интервал.attoseconds) / 1e18,
            процессорноеВремяСекунд: процессор, памятьДо: памятьДо, памятьПосле: памятьПосле,
            граница: "Новый процесс, без прогрева. Интервал — только конструктор ядра с чтением и расшифровкой; ключ и метаданные прочитаны до него, проверка квитанции/модели/хэша и закрытие после. RSS взят до и сразу после открытия, lifetime peak относится ко всему процессу. Кэш ОС не очищается; предшествующая подготовка могла прогреть файлы."))
    } catch { await ядро.закрытьЖурнал(); throw error }
}

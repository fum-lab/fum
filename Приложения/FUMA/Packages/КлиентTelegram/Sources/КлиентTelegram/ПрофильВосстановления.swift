private final class ТранспортПрофиляВосстановления: ТранспортБиблиотеки, @unchecked Sendable {
    private let замок = NSLock()
    private var последний: ЗначениеДанных?
    private var создано = 0
    private var отправлено = 0
    private var приёмов = 0
    let разрешён: Bool
    init(разрешён: Bool) { self.разрешён = разрешён }
    var счётчики: (Int, Int, Int) { замок.withLock { (создано, отправлено, приёмов) } }
    func создатьКлиента() -> Int32 { замок.withLock { создано += 1; return разрешён ? 1 : 0 } }
    func отправить(клиент: Int32, запрос: Data) throws {
        try замок.withLock {
            отправлено += 1
            guard разрешён, клиент == 1 else { throw ОшибкаКлиента.неподдерживаемоеДействие }
            последний = try ЗначениеДанных.прочитать(запрос)
        }
    }
    func принять(таймАут: Double) throws -> Data? {
        замок.withLock { приёмов += 1 }
        throw ОшибкаКлиента.неподдерживаемоеДействие
    }
    func запрос(_ тип: String) throws -> ЗначениеДанных {
        try замок.withLock {
            guard let последний, последний.тип == тип else { throw ОшибкаКлиента.неверныеДанные("Запрос профиля восстановления") }
            return последний
        }
    }
}

@discardableResult
private func ответитьВПрофиле(_ ответ: ЗначениеДанных, на тип: String, ядро: ЯдроКлиента,
                              транспорт: ТранспортПрофиляВосстановления) async throws -> ЗначениеДанных {
    let запрос = try транспорт.запрос(тип)
    guard let корреляция = запрос["@extra"] else { throw ОшибкаКлиента.требуетсяРазбор }
    let событие = try ответ.добавив("@client_id", .число(1)).добавив("@extra", корреляция)
    try await ядро.принять(событие.байты())
    return событие
}

private func черновикВосстановления(_ номер: Int) throws -> Черновик {
    guard (1...256).contains(номер), let идентификатор = UUID(uuidString: String(format: "00000000-0000-4000-8000-%012x", номер)) else {
        throw ОшибкаКлиента.неверныеДанные("Номер черновика профиля")
    }
    let текст = String(format: "r%04d:", номер) + String(repeating: "x", count: 1018)
    return Черновик(идентификатор: идентификатор, аккаунт: 17, канал: -100001,
        действие: .текст(текст), цель: "Синтетический профиль восстановления")
}

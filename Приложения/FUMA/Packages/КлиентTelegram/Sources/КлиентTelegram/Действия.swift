import Foundation
import Darwin

struct ПодготовкаДействия: Sendable {
    let клиент: Int32
    let черновик: Черновик
    let разрешение: РазрешениеДействия
    let поколение: Int
    let начало = ContinuousClock.now
    var группа: Int64?
    var сообщение: ЗначениеДанных?
}

extension ЯдроКлиента {
    /// Явная команда доверенного интерфейса. Локальный preview этот метод не вызывает.
    /// Проверка TDLib может отказать; разрешение не расширяет права сервера.
    public func выполнить(_ клиент: Int32, черновик идентификатор: UUID, разрешение: РазрешениеДействия) throws -> UUID {
        let снимок = try готовый(клиент)
        let черновик = try предпросмотр(идентификатор)
        try разрешение.проверить(черновик)
        guard снимок.аккаунт == черновик.аккаунт else { throw ОшибкаКлиента.доступЗапрещён("Черновик другого аккаунта") }
        guard подготовки.count < 32, отказыПодготовки.count < 256, попытки.count < 256 else { throw ОшибкаКлиента.превышенПредел }
        guard !попытки.values.contains(where: { $0.черновик.идентификатор == идентификатор }),
              !подготовки.values.contains(where: { $0.черновик.идентификатор == идентификатор }) else {
            throw ОшибкаКлиента.требуетсяРазбор
        }
        let попытка = UUID()
        подготовки[попытка] = ПодготовкаДействия(клиент: клиент, черновик: черновик, разрешение: разрешение, поколение: снимок.поколение)
        do { _ = try запрос(.типа("getChat", ["chat_id": .число(черновик.канал)]), клиент: клиент, назначение: .проверкаЧата(попытка)) }
        catch { подготовки.removeValue(forKey: попытка); throw error }
        return попытка
    }
    public func взятьОтказПодготовки(_ идентификатор: UUID) -> ОшибкаКлиента? { отказыПодготовки.removeValue(forKey: идентификатор) }

    func обработатьОтветДействия(_ событие: ЗначениеДанных, ожидание: ОжиданиеОтвета) throws {
        if case .действие(let идентификатор) = ожидание.назначение {
            try принятьОтветОтправки(событие, попытка: идентификатор, клиент: ожидание.клиент)
            return
        }
        if case .сверка(let идентификатор) = ожидание.назначение {
            guard let попытка = попытки[идентификатор], попытка.черновик.аккаунт == клиенты[ожидание.клиент]?.аккаунт else {
                throw ОшибкаКлиента.доступЗапрещён("Сверка другого аккаунта")
            }
            if событие.тип == "messages" {
                guard let сообщения = событие["messages"]?.элементы,
                      сообщения.allSatisfy({ $0 == .пусто || $0["chat_id"]?.целое == попытка.черновик.канал }) else {
                    throw ОшибкаКлиента.неверныеДанные("Сверка истории другого канала")
                }
                try наблюдатьСообщения(событие, клиент: ожидание.клиент)
            }
            // Совпадение содержимого/страница без сообщения не доказывает исход этой попытки.
            return
        }
        let идентификатор: UUID
        switch ожидание.назначение {
        case .проверкаЧата(let номер), .проверкаГруппы(let номер), .проверкаСообщения(let номер), .проверкаСвойств(let номер): идентификатор = номер
        default: throw ОшибкаКлиента.неподдерживаемоеДействие
        }
        guard var подготовка = подготовки[идентификатор] else { return }
        do {
            let снимок = try готовый(ожидание.клиент)
            guard подготовка.клиент == ожидание.клиент, подготовка.поколение == снимок.поколение,
                  ContinuousClock.now - подготовка.начало < .seconds(30) else {
                throw ОшибкаКлиента.доступЗапрещён("Допуск изменился или проверка просрочена")
            }
            guard событие.тип != "error" else { throw ОшибкаКлиента.доступЗапрещён("TDLib отклонила предварительную проверку") }
            let канал = подготовка.черновик.канал
            switch ожидание.назначение {
            case .проверкаЧата:
                guard событие.тип == "chat", событие["id"]?.целое == канал,
                      событие["type"]?.тип == "chatTypeSupergroup", событие["type"]?["is_channel"]?.логическое == true,
                      let группа = событие["type"]?["supergroup_id"]?.целое, группа > 0, группа <= Int32.max else {
                    throw ОшибкаКлиента.доступЗапрещён("Назначение не является точным каналом")
                }
                try сохранитьЧат(событие, номер: канал, клиент: ожидание.клиент)
                подготовка.группа = группа; подготовки[идентификатор] = подготовка
                _ = try запрос(.типа("getSupergroup", ["supergroup_id": .число(группа)]), клиент: ожидание.клиент, назначение: .проверкаГруппы(идентификатор))
            case .проверкаГруппы:
                guard событие.тип == "supergroup", событие["id"]?.целое == подготовка.группа,
                      событие["is_channel"]?.логическое == true, let группа = подготовка.группа else {
                    throw ОшибкаКлиента.доступЗапрещён("Не подтверждён канал собственной учётной записи")
                }
                клиенты[ожидание.клиент]?.супергруппы[группа] = событие
                if let сообщение = подготовка.черновик.действие.сообщение {
                    _ = try запрос(.типа("getMessage", ["chat_id": .число(канал), "message_id": .число(сообщение)]),
                        клиент: ожидание.клиент, назначение: .проверкаСообщения(идентификатор))
                } else { try завершитьПодготовку(идентификатор, свойства: nil) }
            case .проверкаСообщения:
                guard событие.тип == "message", событие["chat_id"]?.целое == канал,
                      let номер = событие["id"]?.целое, номер == подготовка.черновик.действие.сообщение,
                      событие["sending_state"] == nil || событие["sending_state"] == .пусто else {
                    throw ОшибкаКлиента.доступЗапрещён("Редактирование требует точное отправленное сообщение")
                }
                подготовка.сообщение = событие; подготовки[идентификатор] = подготовка
                _ = try запрос(.типа("getMessageProperties", ["chat_id": .число(канал), "message_id": .число(номер)]),
                    клиент: ожидание.клиент, назначение: .проверкаСвойств(идентификатор))
            case .проверкаСвойств:
                guard событие.тип == "messageProperties" else { throw ОшибкаКлиента.неверныеДанные("Нет messageProperties") }
                try завершитьПодготовку(идентификатор, свойства: событие)
            default: break
            }
        } catch let ошибка as ОшибкаКлиента {
            switch ошибка {
            case .доступЗапрещён, .неверныеДанные, .неподдерживаемоеДействие:
                отказыПодготовки[идентификатор] = ошибка; подготовки.removeValue(forKey: идентификатор)
            default: throw ошибка
            }
        }
    }

    func завершитьПодготовку(_ идентификатор: UUID, свойства: ЗначениеДанных?) throws {
        guard let подготовка = подготовки[идентификатор] else { throw ОшибкаКлиента.неверныеДанные("Нет подготовки") }
        let снимок = try готовый(подготовка.клиент)
        guard снимок.поколение == подготовка.поколение, let группа = подготовка.группа,
              let сведения = снимок.супергруппы[группа], сведения["is_channel"]?.логическое == true else {
            throw ОшибкаКлиента.доступЗапрещён("Допуск канала отозван")
        }
        let статус = сведения["status"]
        let создатель = статус?.тип == "chatMemberStatusCreator" && статус?["is_member"]?.логическое == true
        let администратор = статус?.тип == "chatMemberStatusAdministrator"
        guard создатель || администратор else { throw ОшибкаКлиента.доступЗапрещён("Нет административного статуса канала") }
        let допуск = ДопускКанала(аккаунт: подготовка.черновик.аккаунт, канал: подготовка.черновик.канал,
            готов: true, подтверждёнАккаунт: снимок.аккаунтПодтверждён, каналПодтверждён: true,
            можетПисать: создатель || статус?["rights"]?["can_post_messages"]?.логическое == true,
            цельПравки: подготовка.сообщение?["id"]?.целое,
            можетПравить: свойства?["can_be_edited"]?.логическое == true,
            можетЗаменятьМедиа: свойства?["can_edit_media"]?.логическое == true,
            типМедиа: подготовка.сообщение?["content"]?.тип)
        let каталог = корень.appendingPathComponent("вложения").appendingPathComponent(идентификатор.uuidString)
        let данные = try Сериализатор.подготовить(подготовка.черновик, допуск: допуск, каталог: каталог.path)
        try подготовка.разрешение.проверить(подготовка.черновик)
        try сохранитьВложения(подготовка.черновик.действие.вложения, каталог: каталог)
        let попытка = Попытка(черновик: подготовка.черновик, разрешение: подготовка.разрешение, запрос: данные, идентификатор: идентификатор)
        // Долговечное точное намерение предшествует единственной точке send.
        try журнал.добавить(.попытка(попытка))
        попытки[идентификатор] = попытка
        подготовки.removeValue(forKey: идентификатор)
        do { _ = try запрос(данные, клиент: подготовка.клиент, назначение: .действие(идентификатор)) }
        catch {
            var неопределённая = попытка; неопределённая.состояние = .требуетсяРазбор
            try сохранитьПопытку(неопределённая)
            throw error
        }
    }

    func сохранитьПопытку(_ исходная: Попытка) throws {
        let попытка = try сверитьСохранённыеИсходы(исходная, история: модель.история)
        guard попытки[попытка.идентификатор] != попытка else { return }
        try журнал.добавить(.попытка(попытка))
        попытки[попытка.идентификатор] = попытка
    }
    func принятьОтветОтправки(_ событие: ЗначениеДанных, попытка идентификатор: UUID, клиент: Int32) throws {
        guard var попытка = попытки[идентификатор], попытка.черновик.аккаунт == клиенты[клиент]?.аккаунт else {
            throw ОшибкаКлиента.доступЗапрещён("Ответ другой попытки или аккаунта")
        }
        if событие.тип == "error" {
            попытка.кодОшибки = событие["code"]?.целое
            попытка.состояние = (попытка.кодОшибки ?? 500) >= 500 ? .требуетсяРазбор : .отказ
            try сохранитьПопытку(попытка); return
        }
        let сообщения: [ЗначениеДанных]
        if попытка.запрос.тип == "sendMessageAlbum" {
            guard событие.тип == "messages", let элементы = событие["messages"]?.элементы,
                  элементы.count == попытка.черновик.действие.вложения.count else { throw ОшибкаКлиента.неверныеДанные("Неполный исход альбома") }
            сообщения = элементы
        } else { сообщения = [событие] }
        var исходы: [ИсходСообщения] = []
        for сообщение in сообщения {
            guard сообщение.тип == "message", сообщение["chat_id"]?.целое == попытка.черновик.канал,
                  let номер = сообщение["id"]?.целое else { throw ОшибкаКлиента.неверныеДанные("Ответ сообщения другого адресата") }
            try проверитьИдентификатор(номер)
            if let цель = попытка.черновик.действие.сообщение, цель != номер { throw ОшибкаКлиента.неверныеДанные("Ответ другой правки") }
            let состояние = сообщение["sending_state"]
            if состояние?.тип == "messageSendingStatePending" { исходы.append(ИсходСообщения(временный: номер)) }
            else if состояние == nil || состояние == .пусто { исходы.append(ИсходСообщения(временный: номер, окончательный: номер)) }
            else { исходы.append(ИсходСообщения(временный: номер, ошибка: состояние?["error"]?["code"]?.целое ?? 500)) }
        }
        guard Set(исходы.map(\.временный)).count == исходы.count else { throw ОшибкаКлиента.неверныеДанные("Повтор идентичности в альбоме") }
        попытка.сообщения = исходы
        попытка.состояние = исходы.contains { $0.ошибка != nil } ? .отказ : (исходы.allSatisfy { $0.окончательный != nil } ? .выполнено : .ожидает)
        try сохранитьПопытку(попытка)
        try наблюдатьСообщения(событие, клиент: клиент)

    }
    func применитьИсходОтправки(_ событие: ЗначениеДанных, аккаунт: Int64) throws {
        guard ["updateMessageSendSucceeded", "updateMessageSendFailed", "updateDeleteMessages"].contains(событие.тип ?? "") else { return }
        for попытка in попытки.values where попытка.черновик.аккаунт == аккаунт {
            try сохранитьПопытку(попытка)
        }
    }

    /// Повторно читает локальное состояние TDLib/историю; никогда не повторяет send.
    @discardableResult
    public func сверить(_ клиент: Int32, попытка идентификатор: UUID, от: Int64 = 0, толькоМестная: Bool = true) throws -> String {
        let снимок = try готовый(клиент, разрешитьСверку: true)
        guard let попытка = попытки[идентификатор], попытка.черновик.аккаунт == снимок.аккаунт, от >= 0,
              от <= 9_007_199_254_740_991 else { throw ОшибкаКлиента.доступЗапрещён("Нет точной попытки для сверки") }
        return try запрос(.типа("getChatHistory", ["chat_id": .число(попытка.черновик.канал), "from_message_id": .число(от),
            "offset": .число(0), "limit": .число(100), "only_local": .флаг(толькоМестная)]), клиент: клиент, назначение: .сверка(идентификатор), публичный: true)
    }
}

private func сохранитьВложения(_ файлы: [Вложение], каталог: URL) throws {
    guard !файлы.isEmpty else { return }
    let родитель = каталог.deletingLastPathComponent()
    if mkdir(родитель.path, 0o700) != 0, errno != EEXIST { throw ОшибкаКлиента.неверныеДанные("Не создан каталог вложений") }
    var сведения = stat()
    guard lstat(родитель.path, &сведения) == 0, сведения.st_mode & S_IFMT == S_IFDIR,
          сведения.st_mode & 0o777 == 0o700, сведения.st_uid == geteuid(), mkdir(каталог.path, 0o700) == 0 else {
        throw ОшибкаКлиента.доступЗапрещён("Каталог попытки занят или небезопасен")
    }
    var сохранены = Set<String>()
    for файл in файлы {
        let подкаталог = каталог.appendingPathComponent(файл.хэш)
        if mkdir(подкаталог.path, 0o700) != 0, errno != EEXIST { throw ОшибкаКлиента.неверныеДанные("Каталог хэша") }
        let путь = подкаталог.appendingPathComponent(файл.имя)
        if !сохранены.insert(путь.path).inserted { continue }
        let дескриптор = open(путь.path, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        guard дескриптор >= 0 else { throw ОшибкаКлиента.доступЗапрещён("Путь вложения уже занят") }
        defer { Darwin.close(дескриптор) }
        try файл.данные.withUnsafeBytes { буфер in
            var смещение = 0
            while смещение < буфер.count {
                let число = Darwin.write(дескриптор, буфер.baseAddress!.advanced(by: смещение), буфер.count - смещение)
                if число < 0, errno == EINTR { continue }
                guard число > 0 else { throw ОшибкаКлиента.неверныеДанные("Не записаны точные байты вложения") }
                смещение += число
            }
        }
        guard fsync(дескриптор) == 0 else { throw ОшибкаКлиента.требуетсяРазбор }
        guard try Data(contentsOf: путь) == файл.данные else { throw ОшибкаКлиента.требуетсяРазбор }
    }
    for путь in [родитель, каталог] + Array(Set(файлы.map(\.хэш))).map({ каталог.appendingPathComponent($0) }) {
        let дескриптор = open(путь.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard дескриптор >= 0 else { throw ОшибкаКлиента.требуетсяРазбор }
        defer { Darwin.close(дескриптор) }
        guard fsync(дескриптор) == 0 else { throw ОшибкаКлиента.требуетсяРазбор }
    }
}

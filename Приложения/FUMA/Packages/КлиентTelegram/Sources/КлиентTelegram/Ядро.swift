import Foundation
import КонтейнерНаблюдений

public struct НачальныйОтвет: Codable, Equatable, Sendable {
    public let клиент: Int32
    public let корреляция: String
    public let тип: String
}

public struct СнимокКлиента: Sendable {
    public let аккаунт: Int64?
    public internal(set) var авторизация: СостояниеАвторизации = .неизвестно
    /// Приватные сведения для текущего интерфейса: QR, code_info, подсказки и отдельные условия.
    public internal(set) var сведенияАвторизации: ЗначениеДанных = .типа("authorizationStateUnknown")
    public internal(set) var аккаунтПодтверждён = false
    public internal(set) var доказанныйАккаунт: Int64?
    public internal(set) var коррелированныхОтветов = 0
    public internal(set) var начальнаяКорреляция: String?
    public internal(set) var начальныйОтвет: НачальныйОтвет?
    public internal(set) var полученоЗакрытие = false
    public internal(set) var чаты: [Int64: ЗначениеДанных] = [:]
    public internal(set) var супергруппы: [Int64: ЗначениеДанных] = [:]
    public internal(set) var списокЧатовЗагружен = false
    var поколение = 0
}

enum НазначениеЗапроса: Sendable {
    case состояние, авторизация, яСам, чаты, история(чат: Int64), закрытие
    case проверкаЧата(UUID), проверкаГруппы(UUID), проверкаСообщения(UUID), проверкаСвойств(UUID)
    case действие(UUID), сверка(UUID)
}
struct ОжиданиеОтвета: Sendable {
    let клиент: Int32
    let назначение: НазначениеЗапроса
    let публичный: Bool
}
struct ПолученныйОтвет: Sendable {
    let клиент: Int32
    let данные: ЗначениеДанных
}

/// Вся редукция и синхронная запись принадлежат одному actor. В применении события нет await.
public actor ЯдроКлиента {
    let транспорт: any ТранспортБиблиотеки
    let журнал: ЛокальныйЖурнал
    let корень: URL
    var клиенты: [Int32: СнимокКлиента] = [:]
    var ожидаемые: [String: ОжиданиеОтвета] = [:]
    var ответы: [String: ПолученныйОтвет] = [:]
    var черновики: [UUID: Черновик] = [:]
    var попытки: [UUID: Попытка] = [:]
    var подготовки: [UUID: ПодготовкаДействия] = [:]
    var отказыПодготовки: [UUID: ОшибкаКлиента] = [:]
    var доПодтверждения: [Int32: [ЗначениеДанных]] = [:]
    var байтовДоПодтверждения = 0
    var модель = МодельСообщений()
    var остановкаНачата = false
    var разрывВхода = false
    var журналЗакрыт = false

    init(транспорт: any ТранспортБиблиотеки, корень: URL, ключ: Data,
         операцииХранения: ФайловыеОперации = .системные) throws {
        self.транспорт = транспорт; self.корень = корень
        let открытый = try ЛокальныйЖурнал(корень: корень, ключ: ключ, операции: операцииХранения)
        do {
            var модель = МодельСообщений()
            for запись in try открытый.восстановить() {
                switch запись {
                case .черновик(let черновик):
                    try Сериализатор.проверитьСодержимое(черновик)
                    черновики[черновик.идентификатор] = черновик
                case .попытка(let попытка):
                    try попытка.разрешение.проверить(попытка.черновик)
                    попытки[попытка.идентификатор] = попытка.послеПерезапуска()
                case .наблюдение(let аккаунт, let событие): try модель.применить(событие, аккаунт: аккаунт)
                case .разрыв, .неприменённые: разрывВхода = true
                }
            }
            self.модель = модель
            for (номер, попытка) in попытки {
                попытки[номер] = try сверитьСохранённыеИсходы(попытка, история: модель.история).послеПерезапуска()
            }
            журнал = открытый
        } catch { открытый.закрыть(); throw error }
    }

    public func добавитьКлиента(аккаунт: Int64? = nil) throws -> Int32 {
        guard !остановкаНачата, !журналЗакрыт, клиенты.count < 32 else { throw ОшибкаКлиента.закрыт }
        if let аккаунт { try проверитьИдентификатор(аккаунт, положительный: true) }
        let номер = транспорт.создатьКлиента()
        guard номер > 0, клиенты[номер] == nil else { throw ОшибкаКлиента.неверныеДанные("Некорректный client_id") }
        клиенты[номер] = СнимокКлиента(аккаунт: аккаунт)
        клиенты[номер]?.начальнаяКорреляция = try запрос(.типа("getAuthorizationState"), клиент: номер, назначение: .состояние)
        return номер
    }
    public func состояние(_ клиент: Int32) throws -> СнимокКлиента {
        guard let снимок = клиенты[клиент] else { throw ОшибкаКлиента.неверныеДанные("Неизвестный client_id") }
        return снимок
    }
    func готовый(_ клиент: Int32, разрешитьСверку: Bool = false) throws -> СнимокКлиента {
        let снимок = try состояние(клиент)
        guard !остановкаНачата, !журналЗакрыт, снимок.авторизация == .готов,
              снимок.аккаунтПодтверждён, снимок.аккаунт != nil,
              !разрывВхода || разрешитьСверку else { throw ОшибкаКлиента.доступЗапрещён("Нет подтверждённого Ready или необходим разбор входа") }
        return снимок
    }
    @discardableResult
    func запрос(_ данные: ЗначениеДанных, клиент: Int32, назначение: НазначениеЗапроса, публичный: Bool = false) throws -> String {
        let предел: Int
        if case .закрытие = назначение { предел = 160 } else { предел = 128 }
        guard !журналЗакрыт, ожидаемые.count < предел else { throw ОшибкаКлиента.превышенПредел }
        let корреляция = UUID().uuidString
        let байты = try данные.добавив("@extra", .текст(корреляция)).байты()
        ожидаемые[корреляция] = ОжиданиеОтвета(клиент: клиент, назначение: назначение, публичный: публичный)
        do { try транспорт.отправить(клиент: клиент, запрос: байты) }
        catch { ожидаемые.removeValue(forKey: корреляция); throw error }
        return корреляция
    }
    public func взятьОтвет(_ корреляция: String, клиент: Int32) throws -> ЗначениеДанных? {
        guard let ответ = ответы[корреляция] else { return nil }
        guard ответ.клиент == клиент else { throw ОшибкаКлиента.доступЗапрещён("Ответ другого клиента") }
        ответы.removeValue(forKey: корреляция)
        return ответ.данные
    }
    public func авторизовать(_ клиент: Int32, действие: ДействиеАвторизации) throws -> String {
        let снимок = try состояние(клиент)
        guard !остановкаНачата else { throw ОшибкаКлиента.закрыт }
        return try запрос(Авторизация.запрос(действие, состояние: снимок.авторизация), клиент: клиент, назначение: .авторизация, публичный: true)
    }
    @discardableResult
    public func загрузитьЧаты(_ клиент: Int32, предел: Int32 = 100) throws -> String {
        _ = try готовый(клиент, разрешитьСверку: true)
        guard (1...100).contains(предел) else { throw ОшибкаКлиента.неверныеДанные("Предел loadChats первого среза: 1–100") }
        return try запрос(.типа("loadChats", ["chat_list": .типа("chatListMain"), "limit": .число(Int64(предел))]), клиент: клиент, назначение: .чаты, публичный: true)
    }
    @discardableResult
    public func прочитатьИсторию(_ клиент: Int32, чат: Int64, от: Int64 = 0, смещение: Int32 = 0,
                                предел: Int32 = 100, толькоМестная: Bool = true) throws -> String {
        _ = try готовый(клиент, разрешитьСверку: true)
        try проверитьИдентификатор(чат)
        guard от >= 0, от <= 9_007_199_254_740_991, (1...100).contains(предел),
              (-99...0).contains(смещение), предел >= -смещение else { throw ОшибкаКлиента.неверныеДанные("Границы страницы истории") }
        return try запрос(.типа("getChatHistory", ["chat_id": .число(чат), "from_message_id": .число(от),
            "offset": .число(Int64(смещение)), "limit": .число(Int64(предел)), "only_local": .флаг(толькоМестная)]),
            клиент: клиент, назначение: .история(чат: чат), публичный: true)
    }
    public func сохранитьЧерновик(_ черновик: Черновик) throws {
        guard !журналЗакрыт, черновики.count < 256 || черновики[черновик.идентификатор] != nil else { throw ОшибкаКлиента.превышенПредел }
        try Сериализатор.проверитьСодержимое(черновик)
        if let прежний = черновики[черновик.идентификатор], прежний != черновик {
            throw ОшибкаКлиента.доступЗапрещён("Изменённому черновику нужен новый идентификатор")
        }
        try журнал.добавить(.черновик(черновик))
        черновики[черновик.идентификатор] = черновик
    }
    public func предпросмотр(_ идентификатор: UUID) throws -> Черновик {
        guard let черновик = черновики[идентификатор] else { throw ОшибкаКлиента.неверныеДанные("Нет черновика") }
        return черновик
    }
    public func получитьМодельСообщений() -> МодельСообщений { модель }
    public func получитьПопытки() -> [Попытка] { попытки.values.sorted { $0.идентификатор.uuidString < $1.идентификатор.uuidString } }

    public func начатьЗакрытие() throws {
        guard !журналЗакрыт else { throw ОшибкаКлиента.закрыт }
        guard !остановкаНачата else { return }
        остановкаНачата = true
        for номер in клиенты.keys.sorted() where клиенты[номер]?.полученоЗакрытие != true {
            _ = try запрос(.типа("close"), клиент: номер, назначение: .закрытие)
        }
    }
    public var всеЗакрыты: Bool { клиенты.values.allSatisfy { $0.полученоЗакрытие } }
    func закрытьЖурнал() { журнал.закрыть(); журналЗакрыт = true }

    func принять(_ данные: Data) throws {
        do { try применитьВход(данные) }
        catch { разрывВхода = true; throw error }
    }

    private func применитьВход(_ данные: Data) throws {
        guard !журналЗакрыт else { throw ОшибкаКлиента.закрыт }
        let событие = try ЗначениеДанных.прочитать(данные)
        guard let номер = событие["@client_id"]?.целое, let клиент = Int32(exactly: номер), клиенты[клиент] != nil,
              событие.тип != nil else { throw ОшибкаКлиента.неверныеДанные("Неизвестный клиент или тип ответа") }
        if let корреляция = событие["@extra"]?.строка, let ожидание = ожидаемые[корреляция] {
            guard ожидание.клиент == клиент else { throw ОшибкаКлиента.доступЗапрещён("Корреляция другого клиента") }
            if ожидание.публичный, ответы.count >= 256 { throw ОшибкаКлиента.превышенПредел }
            ожидаемые.removeValue(forKey: корреляция)
            do { try обработатьОтвет(событие, ожидание: ожидание) }
            catch { ожидаемые[корреляция] = ожидание; throw error }
            клиенты[клиент]?.коррелированныхОтветов += 1
            if ожидание.публичный { ответы[корреляция] = ПолученныйОтвет(клиент: клиент, данные: событие) }
        } else if событие["@extra"] != nil {
            // Повторный/опоздавший ответ не исполняет действие ещё раз.
            return
        } else if событие.тип == "updateAuthorizationState" {
            guard let состояние = событие["authorization_state"] else { throw ОшибкаКлиента.неверныеДанные("Нет authorization_state") }
            try применитьАвторизацию(состояние, клиент: клиент)
            if состояние.тип == "authorizationStateClosed" {
                try сохранитьНепривязанные(клиент)
                клиенты[клиент]?.полученоЗакрытие = true
            }
        } else if событие.тип == "updateNewChat" {
            guard let чат = событие["chat"], let номер = чат["id"]?.целое else { throw ОшибкаКлиента.неверныеДанные("Нет chat.id") }
            try сохранитьЧат(чат, номер: номер, клиент: клиент)
        } else if событие.тип == "updateChatPosition" {
            guard let номер = событие["chat_id"]?.целое, let позиция = событие["position"] else { throw ОшибкаКлиента.неверныеДанные("Нет позиции чата") }
            try проверитьИдентификатор(номер)
            let новые = try действующиеПозицииЧата([позиция])
            if var чат = клиенты[клиент]?.чаты[номер] {
                var позиции = чат["positions"]?.элементы ?? []
                позиции.removeAll { $0["list"] == позиция["list"] }
                позиции.append(contentsOf: новые)
                чат = try чат.добавив("positions", .массив(позиции))
                клиенты[клиент]?.чаты[номер] = чат
            }
        } else if событие.тип == "updateChatLastMessage" || событие.тип == "updateChatDraftMessage" {
            let поле = событие.тип == "updateChatLastMessage" ? "last_message" : "draft_message"
            guard let номер = событие["chat_id"]?.целое, let содержимое = событие[поле],
                  let позиции = событие["positions"]?.элементы else { throw ОшибкаКлиента.неверныеДанные("Неполное обновление чата") }
            try проверитьИдентификатор(номер)
            let новые = try действующиеПозицииЧата(позиции)
            guard содержимое == .пусто || (поле == "last_message" ?
                содержимое.тип == "message" && содержимое["chat_id"]?.целое == номер : содержимое.тип == "draftMessage") else {
                throw ОшибкаКлиента.неверныеДанные("Неверное содержимое обновления чата")
            }
            if var чат = клиенты[клиент]?.чаты[номер] {
                чат = try чат.добавив(поле, содержимое).добавив("positions", .массив(новые))
                клиенты[клиент]?.чаты[номер] = чат
            }
        } else if событие.тип == "updateSupergroup" {
            guard let группа = событие["supergroup"], let номер = группа["id"]?.целое else { throw ОшибкаКлиента.неверныеДанные("Нет supergroup.id") }
            guard (клиенты[клиент]?.супергруппы.count ?? 0) < 4096 || клиенты[клиент]?.супергруппы[номер] != nil else { throw ОшибкаКлиента.превышенПредел }
            клиенты[клиент]?.супергруппы[номер] = группа
            клиенты[клиент]?.поколение += 1
        } else { try наблюдатьСообщения(событие, клиент: клиент) }
    }

    func применитьАвторизацию(_ значение: ЗначениеДанных, клиент: Int32) throws {
        let новое = СостояниеАвторизации(тип: значение.тип ?? "")
        let прежнее = клиенты[клиент]!.авторизация
        guard прежнее != .закрыт || новое == .закрыт else { throw ОшибкаКлиента.неверныеДанные("Closed терминален") }
        клиенты[клиент]?.авторизация = новое
        клиенты[клиент]?.сведенияАвторизации = значение
        if новое != .готов {
            клиенты[клиент]?.аккаунтПодтверждён = false
            клиенты[клиент]?.поколение += 1
        } else if прежнее != .готов, клиенты[клиент]?.аккаунт != nil, !остановкаНачата {
            _ = try запрос(.типа("getMe"), клиент: клиент, назначение: .яСам)
        }
    }
    func сохранитьЧат(_ чат: ЗначениеДанных, номер: Int64, клиент: Int32) throws {
        try проверитьИдентификатор(номер)
        guard (клиенты[клиент]?.чаты.count ?? 0) < 4096 || клиенты[клиент]?.чаты[номер] != nil else { throw ОшибкаКлиента.превышенПредел }
        клиенты[клиент]?.чаты[номер] = чат
    }
    func наблюдатьСообщения(_ событие: ЗначениеДанных, клиент: Int32) throws {
        let типы = ["message", "messages", "updateNewMessage", "updateMessageSendSucceeded", "updateMessageSendFailed", "updateMessageContent", "updateMessageEdited", "updateDeleteMessages"]
        guard типы.contains(событие.тип ?? "") else { return }
        guard let аккаунт = клиенты[клиент]?.доказанныйАккаунт else {
            let размер = try событие.байты().count
            guard (доПодтверждения[клиент]?.count ?? 0) < 64, размер <= 8 * 1024 * 1024 - байтовДоПодтверждения else {
                throw ОшибкаКлиента.превышенПредел
            }
            доПодтверждения[клиент, default: []].append(событие)
            байтовДоПодтверждения += размер
            return
        }
        var следующая = модель
        try следующая.применить(событие, аккаунт: аккаунт)
        if следующая.история.count != модель.история.count {
            try журнал.добавить(.наблюдение(аккаунт: аккаунт, событие: событие))
            модель = следующая
            try применитьИсходОтправки(событие, аккаунт: аккаунт)
        }
    }
    func обработатьОтвет(_ событие: ЗначениеДанных, ожидание: ОжиданиеОтвета) throws {
        let клиент = ожидание.клиент
        switch ожидание.назначение {
        case .состояние:
            if событие.тип != "error" { try применитьАвторизацию(событие, клиент: клиент) }
            if let корреляция = событие["@extra"]?.строка,
               корреляция == клиенты[клиент]?.начальнаяКорреляция, let тип = событие.тип {
                клиенты[клиент]?.начальныйОтвет = НачальныйОтвет(клиент: клиент, корреляция: корреляция, тип: тип)
            }
        case .яСам:
            guard событие.тип == "user", событие["id"]?.целое == клиенты[клиент]?.аккаунт,
                  клиенты[клиент]?.авторизация == .готов else {
                клиенты[клиент]?.аккаунтПодтверждён = false
                try сохранитьНепривязанные(клиент)
                return
            }
            клиенты[клиент]?.аккаунтПодтверждён = true
            клиенты[клиент]?.доказанныйАккаунт = событие["id"]?.целое
            while let событие = доПодтверждения[клиент]?.first {
                let размер = try событие.байты().count
                try наблюдатьСообщения(событие, клиент: клиент)
                доПодтверждения[клиент]?.removeFirst()
                байтовДоПодтверждения -= размер
            }
            доПодтверждения.removeValue(forKey: клиент)
        case .чаты:
            if событие.тип == "error", событие["code"]?.целое == 404 { клиенты[клиент]?.списокЧатовЗагружен = true }
        case .история(let чат):
            if событие.тип == "messages" {
                guard let элементы = событие["messages"]?.элементы,
                      элементы.allSatisfy({ $0 == .пусто || $0["chat_id"]?.целое == чат }) else {
                    throw ОшибкаКлиента.неверныеДанные("История другого чата")
                }
                try наблюдатьСообщения(событие, клиент: клиент)
            }
        case .авторизация, .закрытие: break
        default: try обработатьОтветДействия(событие, ожидание: ожидание)
        }
    }

    func сохранитьНепривязанные(_ клиент: Int32) throws {
        guard let события = доПодтверждения[клиент], !события.isEmpty else { return }
        try журнал.добавить(.разрыв("Не доказана идентичность аккаунта; обновления сохранены без присвоения аккаунту"))
        разрывВхода = true
        for событие in события { try журнал.добавить(.неприменённые([событие.байты()])) }
        байтовДоПодтверждения -= try события.reduce(0) { try $0 + $1.байты().count }
        доПодтверждения.removeValue(forKey: клиент)
    }

    /// Вызывается только внешним владельцем после присоединения обоих потоков.
    /// При ошибке сохранения журнал и единственная копия хвоста остаются у владельца.
    func завершитьПриём(хвост: [Data], причина: ОшибкаКлиента?) throws -> Bool {
        остановкаНачата = true
        if причина != nil || !всеЗакрыты || !хвост.isEmpty {
            разрывВхода = true
            try журнал.добавить(.разрыв("Не подтверждено полное закрытие или применение входа; необходим разбор"))
            for данные in хвост { try журнал.добавить(.неприменённые([данные])) }
        }
        for клиент in клиенты.keys.sorted() { try сохранитьНепривязанные(клиент) }
        закрытьЖурнал()
        return разрывВхода
    }
}

/// order — строковый int64 TDLib; ноль удаляет только принадлежность списку.
private func действующиеПозицииЧата(_ позиции: [ЗначениеДанных]) throws -> [ЗначениеДанных] {
    var результат: [ЗначениеДанных] = []
    var списки: [ЗначениеДанных] = []
    for позиция in позиции {
        guard позиция.тип == "chatPosition", let список = позиция["list"], список.тип != nil,
              let строка = позиция["order"]?.строка, let порядок = Int64(строка), порядок >= 0,
              !списки.contains(список) else { throw ОшибкаКлиента.неверныеДанные("Неверная или повторная позиция чата") }
        списки.append(список)
        if порядок != 0 { результат.append(позиция) }
    }
    return результат
}

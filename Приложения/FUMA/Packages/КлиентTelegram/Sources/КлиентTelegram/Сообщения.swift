import Foundation

public struct ИдентичностьСообщения: Hashable, Codable, Sendable {
    public var сервис: String { "Telegram" }
    public let аккаунт: Int64
    public let чат: Int64
    public let сообщение: Int64
    public init(аккаунт: Int64, чат: Int64, сообщение: Int64) {
        self.аккаунт = аккаунт; self.чат = чат; self.сообщение = сообщение
    }
}

public struct СнимокСообщения: Codable, Equatable, Sendable {
    public var данные: ЗначениеДанных
    public var удалено = false
    public var очищенКэш = false
}

public struct НаблюдениеСообщения: Codable, Equatable, Sendable {
    public let порядок: Int
    public let аккаунт: Int64
    public let событие: ЗначениеДанных
}

public struct МодельСообщений: Sendable {
    public internal(set) var сообщения: [ИдентичностьСообщения: СнимокСообщения] = [:]
    public internal(set) var история: [НаблюдениеСообщения] = []
    private var замены: [ИдентичностьСообщения: ИдентичностьСообщения] = [:]
    public init() {}

    mutating func применить(_ событие: ЗначениеДанных, аккаунт: Int64) throws {
        guard история.count < 4096 else { throw ОшибкаКлиента.превышенПредел }
        try проверитьИдентификатор(аккаунт, положительный: true)
        func идентичность(_ объект: ЗначениеДанных, поле: String = "message_id") throws -> ИдентичностьСообщения {
            guard let чат = объект["chat_id"]?.целое, let номер = объект[поле]?.целое else {
                throw ОшибкаКлиента.неверныеДанные("Нет идентичности сообщения")
            }
            try проверитьИдентификатор(чат); try проверитьИдентификатор(номер)
            return ИдентичностьСообщения(аккаунт: аккаунт, чат: чат, сообщение: номер)
        }
        func получитьСообщение(_ объект: ЗначениеДанных) throws -> (ИдентичностьСообщения, СнимокСообщения) {
            guard объект.тип == "message", объект["content"]?.тип != nil else {
                throw ОшибкаКлиента.неверныеДанные("Нет содержимого message")
            }
            let ключ = try идентичность(объект, поле: "id")
            var новое = сообщения[ключ] ?? СнимокСообщения(данные: объект)
            новое.данные = объект; новое.очищенКэш = false
            return (ключ, новое)
        }
        var следующий = сообщения
        var следующиеЗамены = замены
        switch событие.тип {
        case "message":
            let (ключ, значение) = try получитьСообщение(событие)
            if замены[ключ] == nil { следующий[ключ] = значение }
        case "messages":
            guard let элементы = событие["messages"]?.элементы, элементы.count <= 100 else {
                throw ОшибкаКлиента.неверныеДанные("Страница messages: до 100 элементов")
            }
            for сообщение in элементы where сообщение != .пусто {
                let (ключ, значение) = try получитьСообщение(сообщение)
                if замены[ключ] == nil { следующий[ключ] = значение }
            }
        case "updateNewMessage", "updateMessageSendSucceeded", "updateMessageSendFailed":
            guard let сообщение = событие["message"] else { throw ОшибкаКлиента.неверныеДанные("Нет message") }
            let (ключ, значение) = try получитьСообщение(сообщение); следующий[ключ] = значение
            if let старый = событие["old_message_id"]?.целое, старый != ключ.сообщение {
                let старыйКлюч = ИдентичностьСообщения(аккаунт: аккаунт, чат: ключ.чат, сообщение: старый)
                // Переход временного ID сохраняется в исходном событии истории.
                следующий.removeValue(forKey: старыйКлюч)
                следующиеЗамены[старыйКлюч] = ключ
            }
        case "updateMessageContent", "updateMessageEdited":
            let ключ = try идентичность(событие)
            var снимок = следующий[ключ] ?? СнимокСообщения(данные: .типа("message", [
                "chat_id": .число(ключ.чат), "id": .число(ключ.сообщение)]))
            if событие.тип == "updateMessageContent" {
                guard let содержимое = событие["new_content"], содержимое.тип != nil else {
                    throw ОшибкаКлиента.неверныеДанные("Нет new_content")
                }
                снимок.данные = try снимок.данные.добавив("content", содержимое)
            } else {
                guard let дата = событие["edit_date"]?.целое, дата >= 0 else { throw ОшибкаКлиента.неверныеДанные("Нет edit_date") }
                снимок.данные = try снимок.данные.добавив("edit_date", .число(дата))
                снимок.данные = try снимок.данные.добавив("reply_markup", событие["reply_markup"] ?? .пусто)
            }
            следующий[ключ] = снимок
        case "updateDeleteMessages":
            guard let чат = событие["chat_id"]?.целое, let номера = событие["message_ids"]?.элементы,
                  let окончательно = событие["is_permanent"]?.логическое, let кэш = событие["from_cache"]?.логическое else {
                throw ОшибкаКлиента.неверныеДанные("Неполное удаление")
            }
            try проверитьИдентификатор(чат)
            for значение in номера {
                guard let номер = значение.целое else { throw ОшибкаКлиента.неверныеДанные("Номер удаления") }
                try проверитьИдентификатор(номер)
                let ключ = ИдентичностьСообщения(аккаунт: аккаунт, чат: чат, сообщение: номер)
                var снимок = следующий[ключ] ?? СнимокСообщения(данные: .типа("message", ["chat_id": .число(чат), "id": .число(номер)]))
                снимок.удалено = снимок.удалено || окончательно
                снимок.очищенКэш = снимок.очищенКэш || кэш
                следующий[ключ] = снимок
            }
        default: return
        }
        guard следующий.count <= 4096 else { throw ОшибкаКлиента.превышенПредел }
        сообщения = следующий
        замены = следующиеЗамены
        // Повтор не теряет место в истории, но не создаёт вторую идентичность.
        история.append(НаблюдениеСообщения(порядок: история.count + 1, аккаунт: аккаунт, событие: событие))
    }
}

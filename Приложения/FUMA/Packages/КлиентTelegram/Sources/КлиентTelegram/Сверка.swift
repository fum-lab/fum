import Foundation

/// Одна редукция доказательств используется при живом приёме и восстановлении. Она никогда не отправляет запросы.
func сверитьСохранённыеИсходы(_ исходная: Попытка, история: [НаблюдениеСообщения]) throws -> Попытка {
    guard исходная.запрос.тип == "sendMessage" || исходная.запрос.тип == "sendMessageAlbum", !исходная.сообщения.isEmpty else { return исходная }
    var попытка = исходная
    for наблюдение in история where наблюдение.аккаунт == попытка.черновик.аккаунт {
        let событие = наблюдение.событие
        if событие.тип == "updateDeleteMessages", событие["chat_id"]?.целое == попытка.черновик.канал,
           событие["from_cache"]?.логическое == false, let номера = событие["message_ids"]?.элементы {
            let удалённые = Set(номера.compactMap(\.целое))
            if попытка.сообщения.contains(where: { удалённые.contains($0.временный) && $0.окончательный == nil && $0.ошибка == nil }) {
                попытка.противоречие = true
            }
            continue
        }
        guard событие.тип == "updateMessageSendSucceeded" || событие.тип == "updateMessageSendFailed",
              let старый = событие["old_message_id"]?.целое, let сообщение = событие["message"],
              сообщение["chat_id"]?.целое == попытка.черновик.канал,
              let позиция = попытка.сообщения.firstIndex(where: { $0.временный == старый }) else { continue }
        guard let новый = сообщение["id"]?.целое else { throw ОшибкаКлиента.неверныеДанные("Неполный исход сообщения") }
        try проверитьИдентификатор(новый)
        if событие.тип == "updateMessageSendSucceeded" {
            if попытка.сообщения[позиция].ошибка != nil || (попытка.сообщения[позиция].окончательный != nil && попытка.сообщения[позиция].окончательный != новый) {
                попытка.противоречие = true
            } else { попытка.сообщения[позиция].окончательный = новый }
        } else {
            if попытка.сообщения[позиция].окончательный != nil { попытка.противоречие = true }
            попытка.сообщения[позиция].ошибка = событие["error"]?["code"]?.целое ?? 500
        }
    }
    if попытка.противоречие { попытка.состояние = .требуетсяРазбор }
    else if попытка.сообщения.allSatisfy({ $0.окончательный != nil }) { попытка.состояние = .выполнено }
    else if попытка.сообщения.contains(where: { $0.ошибка != nil }) { попытка.состояние = .отказ }
    return попытка
}

import Foundation
import Testing
@testable import КлиентTelegram

/// Последовательно с остальными проверками единственного владельца receive.
func проверитьПрофильСинтетическогоПотока() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let результат = try await измеритьСинтетическийПоток(корень: каталог, ключ: Data(repeating: 51, count: 32), количество: 16)
    let отчёт = try ЗначениеДанных.прочитать(результат)
    #expect(отчёт["схема"]?.строка == "fum.профиль-клиента.1")
    #expect(отчёт["сценарий"]?.строка == "поток")
    #expect(отчёт["измеряемыхКадров"]?.целое == 16)
    #expect(отчёт["кадровПрогрева"]?.целое == 32)
    #expect(отчёт["байтовКадра"]?.целое == 4096)
    #expect(отчёт["получено"]?.целое == 48)
    #expect(отчёт["применено"]?.целое == 48)
    #expect(отчёт["неприменено"]?.целое == 0)
    #expect(отчёт["клиентов"]?.целое == 2)
    #expect(отчёт["ошибок"]?.целое == 0)
    #expect(отчёт["порядокСохранён"]?.логическое == true)
    #expect(отчёт["фикстурыШа256"]?.строка?.count == 64)
    #expect(отчёт["байтыСохранены"]?.логическое == true)
    #expect(отчёт["полученныеШа256"]?.строка == отчёт["фикстурыШа256"]?.строка)
    let полученоБайтов = try #require(отчёт["полученоБайтов"]?.целое)
    let ожидаемыйРазмер: Int64 = 48 * 4096
    #expect(полученоБайтов == ожидаемыйРазмер)
    for имя in ["передача", "обработка"] {
        let ряд = try #require(отчёт[имя])
        #expect(ряд["число"]?.целое == 16)
        let середина = try #require(ряд["процентиль50Наносекунд"]?.целое)
        let хвост = try #require(ряд["процентиль95Наносекунд"]?.целое)
        #expect(середина >= 0 && хвост >= середина)
    }
    #expect(отчёт["памятьДо"]?["текущая"]?.целое ?? 0 > 0)
    #expect(отчёт["памятьПосле"]?["текущая"]?.целое ?? 0 > 0)
    await #expect(throws: ОшибкаКлиента.self) {
        try await измеритьСинтетическийПоток(корень: каталог, ключ: Data(repeating: 51, count: 32), количество: 0)
    }
    let отмена = try ЗначениеДанных.прочитать(await измеритьСинтетическуюОтмену(количество: 2))
    #expect(отмена["схема"]?.строка == "fum.профиль-клиента.1")
    #expect(отмена["сценарий"]?.строка == "отмена")
    #expect(отмена["измеряемыхОтмен"]?.целое == 2)
    #expect(отмена["повторовПрогрева"]?.целое == 5)
    #expect(отмена["хвостовПроверено"]?.целое == 7)
    #expect(отмена["полученоКадров"]?.целое == 28)
    #expect(отмена["непримененоКадров"]?.целое == 28)
    #expect(отмена["примененоКадров"]?.целое == 0)
    #expect(отмена["пикКадровОчереди"]?.целое == 2)
    #expect(отмена["пикБайтовОчереди"]?.целое == 8192)
    #expect(отмена["задержка"]?["число"]?.целое == 2)
    #expect(отмена["байтыСохранены"]?.логическое == true)
    await #expect(throws: ОшибкаКлиента.self) { try await измеритьСинтетическуюОтмену(количество: 0) }

}

private final class УправляемаяСинхронизация: @unchecked Sendable {
    private let замок = NSLock()
    private var отказ = false
    func включитьОтказ() { замок.withLock { отказ = true } }
    func выполнить(_ дескриптор: Int32) throws {
        if замок.withLock({ отказ }) { throw ОшибкаКлиента.требуетсяРазбор }
        try ФайловыеОперации.системные.синхронизация(дескриптор)
    }
}

private final class ТранспортСНеопределённойОтправкой: ТранспортБиблиотеки, Sendable {
    let базовый = ЗаписывающийТранспорт()
    func создатьКлиента() -> Int32 { базовый.создатьКлиента() }
    func принять(таймАут: Double) throws -> Data? { try базовый.принять(таймАут: таймАут) }
    func отправить(клиент: Int32, запрос: Data) throws {
        try базовый.отправить(клиент: клиент, запрос: запрос)
        if try ЗначениеДанных.прочитать(запрос).тип == "sendMessage" { throw ОшибкаКлиента.требуетсяРазбор }
    }
}

@Test func отказСинхронизацииНамеренияПредшествуетОтправке() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let управление = УправляемаяСинхронизация()
    var операции = ФайловыеОперации.системные
    операции.синхронизация = { try управление.выполнить($0) }
    let транспорт = ЗаписывающийТранспорт(), ключ = Data(repeating: 12, count: 32)
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: ключ, операцииХранения: операции)
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Не отправлять до fsync"), цель: "Инъекция отказа")
    try await ядро.сохранитьЧерновик(черновик)
    let разрешение = try РазрешениеДействия(черновик: черновик, основание: "Точное действие синтетики")
    _ = try await ядро.выполнить(клиент, черновик: черновик.идентификатор, разрешение: разрешение)
    управление.включитьОтказ()
    await #expect(throws: (any Error).self) { try await провестиПроверкуЧата(ядро, клиент: клиент, транспорт: транспорт) }
    #expect(!транспорт.отправленные.contains { $0.1.тип == "sendMessage" })
    #expect(await ядро.получитьПопытки().isEmpty)
    await ядро.закрытьЖурнал()
}

@Test func ошибкаПослеВызоваТранспортаНеПовторяетОтправкуПриВосстановлении() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ТранспортСНеопределённойОтправкой(), ключ = Data(repeating: 13, count: 32)
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: ключ)
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт.базовый)
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Неизвестный исход"), цель: "Инъекция отказа транспорта")
    try await ядро.сохранитьЧерновик(черновик)
    let разрешение = try РазрешениеДействия(черновик: черновик, основание: "Одна попытка синтетики")
    let номер = try await ядро.выполнить(клиент, черновик: черновик.идентификатор, разрешение: разрешение)
    await #expect(throws: (any Error).self) { try await провестиПроверкуЧата(ядро, клиент: клиент, транспорт: транспорт.базовый) }
    #expect(транспорт.базовый.отправленные.filter { $0.1.тип == "sendMessage" }.count == 1)
    #expect(await ядро.получитьПопытки().first { $0.идентификатор == номер }?.состояние == .требуетсяРазбор)
    await ядро.закрытьЖурнал()
    let новыйТранспорт = ЗаписывающийТранспорт()
    let восстановленное = try ЯдроКлиента(транспорт: новыйТранспорт, корень: каталог, ключ: ключ)
    let сохранённая = try #require(await восстановленное.получитьПопытки().first { $0.идентификатор == номер })
    #expect(сохранённая.состояние == .требуетсяРазбор && сохранённая.черновик == черновик)
    #expect(новыйТранспорт.отправленные.isEmpty)
    await восстановленное.закрытьЖурнал()
}

/// Таймер не закрывает очередь и не отменяет цикл. Последующая остановка — только очистка.
private func проверитьСамостоятельноеЗавершение(_ цикл: ЦиклПриёма) async {
    let завершено = СигналФазыПриёма()
    Task {
        await цикл.дождатьсяЗавершенияПотоков()
        завершено.сообщить()
    }
    #expect(await завершено.ждать(), "Аварийный путь должен сам завершить оба потока до остановки")
}

/// Вызывается внутри единственного последовательного теста владельца receive.
func проверитьАварийныеВеткиПриёма() async throws {
    let большой = Data(repeating: 2, count: 9)
    let транспортБольшого = ТранспортФазПриёма([Data([1]), большой], барьерНа: 1)
    let записьБольшого = ЗаписьФазПриёма()
    let большойЦикл = try ЦиклПриёма(транспорт: транспортБольшого, ёмкость: 2, пределБайтов: 8) { await записьБольшого.добавить($0) }
    try большойЦикл.запустить()
    #expect(await транспортБольшого.достигнут.ждать())
    await проверитьСамостоятельноеЗавершение(большойЦикл)
    await большойЦикл.остановить()
    #expect(await записьБольшого.данные == [Data([1])])
    #expect(большойЦикл.незавершённые == [большой])
    #expect(большойЦикл.причинаОстановки == .превышенПредел)
    #expect(транспортБольшого.вызовов == 2)

    let кадры = [Data([1]), Data([2]), Data([3])]
    let разрешитьОбработку = СигналФазыПриёма()
    let записьТранспорта = ЗаписьФазПриёма()
    let отказТранспорта = ОшибкаКлиента.неверныеДанные("Синтетический отказ транспорта")
    let транспортОтказа = ТранспортФазПриёма(кадры, барьерНа: 3, ошибкаПосле: отказТранспорта)
    let циклОтказа = try ЦиклПриёма(транспорт: транспортОтказа, ёмкость: 2, пределБайтов: 8) { кадр in
        if кадр == Data([1]) { #expect(await разрешитьОбработку.ждать()) }
        await записьТранспорта.добавить(кадр)
    }
    try циклОтказа.запустить()
    #expect(await транспортОтказа.достигнут.ждать())
    #expect(циклОтказа.пикКоличество == 2)
    разрешитьОбработку.сообщить()
    await проверитьСамостоятельноеЗавершение(циклОтказа)
    await циклОтказа.остановить()
    #expect(await записьТранспорта.данные == кадры)
    #expect(циклОтказа.незавершённые.isEmpty)
    #expect(циклОтказа.причинаОстановки == отказТранспорта)

    let разрешитьОшибка = СигналФазыПриёма()
    let разрешитьПоследний = СигналФазыПриёма()
    let всеКадры = кадры + [Data([4])]
    let транспортХвоста = ТранспортФазПриёма(всеКадры, барьерНа: 3, разрешение: разрешитьПоследний)
    let начатые = ЗаписьФазПриёма()
    let отказОбработчика = ОшибкаКлиента.неверныеДанные("Синтетический отказ обработчика")
    let циклХвоста = try ЦиклПриёма(транспорт: транспортХвоста, ёмкость: 2, пределБайтов: 8) { кадр in
        await начатые.добавить(кадр)
        #expect(await разрешитьОшибка.ждать())
        throw отказОбработчика
    }
    try циклХвоста.запустить()
    // Этот вызов возможен только после допуска первых трёх кадров:
    // один удерживает обработчик, два заполняют очередь, четвёртый — транспорт.
    #expect(await транспортХвоста.достигнут.ждать())
    #expect(циклХвоста.пикКоличество == 2)
    разрешитьОшибка.сообщить()
    разрешитьПоследний.сообщить()
    await проверитьСамостоятельноеЗавершение(циклХвоста)
    await циклХвоста.остановить(освободитьВладение: false)
    #expect(await начатые.данные == [Data([1])])
    #expect(циклХвоста.незавершённые == всеКадры)
    #expect(циклХвоста.причинаОстановки == отказОбработчика)
    #expect(транспортХвоста.вызовов == 4)
    let следующий = try ЦиклПриёма(транспорт: ТранспортФазПриёма([], барьерНа: -1)) { _ in }
    #expect(throws: ОшибкаКлиента.ужеЕстьПриёмник) { try следующий.запустить() }
    циклХвоста.освободитьВладение()
    try следующий.запустить()
    await следующий.остановить()
    await циклХвоста.остановить()
    #expect(циклХвоста.незавершённые == всеКадры)
}

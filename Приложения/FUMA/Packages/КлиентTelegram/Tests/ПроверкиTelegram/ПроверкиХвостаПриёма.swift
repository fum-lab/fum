private final class СигналФазыПриёма: @unchecked Sendable {
    private let условие = NSCondition()
    private var готов = false
    private var ожидающие: [UUID: CheckedContinuation<Bool, Never>] = [:]
    func сообщить() {
        let продолжения = условие.withLock {
            готов = true
            let результат = Array(ожидающие.values); ожидающие.removeAll()
            условие.broadcast()
            return результат
        }
        for продолжение in продолжения { продолжение.resume(returning: true) }
    }
    func ждать() async -> Bool {
        let идентификатор = UUID()
        return await withCheckedContinuation { продолжение in
            let сразу = условие.withLock {
                if готов { return true }
                ожидающие[идентификатор] = продолжение
                return false
            }
            if сразу { продолжение.resume(returning: true) }
            else {
                DispatchQueue.global().asyncAfter(deadline: .now() + 3) { [self] in
                    let истёкшее = условие.withLock { ожидающие.removeValue(forKey: идентификатор) }
                    истёкшее?.resume(returning: false)
                }
            }
        }
    }
    func ждатьВПотоке() throws {
        условие.lock(); defer { условие.unlock() }
        let край = Date(timeIntervalSinceNow: 3)
        while !готов {
            guard условие.wait(until: край) || готов else { throw ОшибкаКлиента.неверныеДанные("Не освобождён синтетический барьер") }
        }
    }
}

private final class ТранспортФазПриёма: ТранспортБиблиотеки, @unchecked Sendable {
    private let замок = NSLock()
    private var номер = 0
    private let кадры: [Data]
    private let барьерНа: Int
    private let разрешение: СигналФазыПриёма?
    private let ошибкаПосле: ОшибкаКлиента?
    let достигнут = СигналФазыПриёма()
    var вызовов: Int { замок.withLock { номер } }
    init(_ кадры: [Data], барьерНа: Int, разрешение: СигналФазыПриёма? = nil, ошибкаПосле: ОшибкаКлиента? = nil) {
        self.кадры = кадры; self.барьерНа = барьерНа; self.разрешение = разрешение; self.ошибкаПосле = ошибкаПосле
    }
    func создатьКлиента() -> Int32 { 1 }
    func отправить(клиент: Int32, запрос: Data) throws {}
    func принять(таймАут: Double) throws -> Data? {
        let позиция = замок.withLock { let текущий = номер; номер += 1; return текущий }
        if позиция == барьерНа { достигнут.сообщить(); try разрешение?.ждатьВПотоке() }
        if позиция < кадры.count { return кадры[позиция] }
        if let ошибкаПосле { throw ошибкаПосле }
        Thread.sleep(forTimeInterval: таймАут)
        return nil
    }
}

private actor ЗаписьФазПриёма {
    var данные: [Data] = []
    func добавить(_ кадр: Data) { данные.append(кадр) }
}


@Test(arguments: [false, true])
func частичныйОтказАльбомаСохраняетНеопределённость(_ отказВОтвете: Bool) async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт(), ключ = Data(repeating: 9, count: 32)
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: ключ)
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let файл = Вложение(имя: "альбом.txt", данные: Data([1, 2, 3]))
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: .альбом([файл, файл], nil), цель: "Проверка частичного отказа")
    try await ядро.сохранитьЧерновик(черновик)
    let разрешение = try РазрешениеДействия(черновик: черновик, основание: "Точный синтетический альбом")
    let номер = try await ядро.выполнить(клиент, черновик: черновик.идентификатор, разрешение: разрешение)
    try await провестиПроверкуЧата(ядро, клиент: клиент, транспорт: транспорт)
    let запрос = транспорт.отправленные.last!.1
    let отказ = try отказПримера(110, новый: отказВОтвете ? 110 : 210)
    let первый = отказВОтвете ? отказ["message"]! : сообщениеПримера(110, тип: "messageDocument", ожидает: true)
    try await доставить(.типа("messages", ["total_count": .число(2), "messages": .массив([
        первый, сообщениеПримера(111, тип: "messageDocument", ожидает: true)])]), клиент: клиент, ядро: ядро, запрос: запрос)
    if !отказВОтвете { try await доставить(отказ, клиент: клиент, ядро: ядро) }
    let до = try #require(await ядро.получитьПопытки().first { $0.идентификатор == номер })
    #expect(до.состояние == .ожидает)
    #expect(до.сообщения[0].ошибка == 429)
    #expect(до.сообщения[1].окончательный == nil && до.сообщения[1].ошибка == nil)
    await ядро.закрытьЖурнал()
    let новыйТранспорт = ЗаписывающийТранспорт()
    let восстановленное = try ЯдроКлиента(транспорт: новыйТранспорт, корень: каталог, ключ: ключ)
    let после = try #require(await восстановленное.получитьПопытки().first { $0.идентификатор == номер })
    #expect(после.состояние == .требуетсяРазбор)
    #expect(после.сообщения == до.сообщения)
    #expect(новыйТранспорт.отправленные.isEmpty)
    let новыйКлиент = try await готовыйКлиент(восстановленное, транспорт: новыйТранспорт)
    try await доставить(.типа("updateMessageSendSucceeded", ["old_message_id": .число(111),
        "message": сообщениеПримера(10111, тип: "messageDocument")]), клиент: новыйКлиент, ядро: восстановленное)
    let законченная = try #require(await восстановленное.получитьПопытки().first { $0.идентификатор == номер })
    #expect(законченная.состояние == .отказ)
    #expect(законченная.сообщения[0].ошибка == 429 && законченная.сообщения[1].окончательный == 10111)
    #expect(!новыйТранспорт.отправленные.contains { $0.1.тип == "sendMessageAlbum" })
    await восстановленное.закрытьЖурнал()
}

@Test(arguments: ["ранний-отказ", "успех-отказ", "отказ-успех"])
func отказПовторыИПротиворечияПереживаютПерезапуск(_ порядок: String) async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт(), ключ = Data(repeating: 11, count: 32)
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: ключ)
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Синтетическая отправка"), цель: "Проверка исходов")
    try await ядро.сохранитьЧерновик(черновик)
    let разрешение = try РазрешениеДействия(черновик: черновик, основание: "Одно точное действие фикстуры")
    let номер = try await ядро.выполнить(клиент, черновик: черновик.идентификатор, разрешение: разрешение)
    try await провестиПроверкуЧата(ядро, клиент: клиент, транспорт: транспорт)
    let запрос = транспорт.отправленные.last!.1
    let отказ = try отказПримера(101, новый: 201, тип: "messageText")
    let успех = ЗначениеДанных.типа("updateMessageSendSucceeded", ["old_message_id": .число(101),
        "message": сообщениеПримера(10001, тип: "messageText")])
    if порядок == "ранний-отказ" { try await доставить(отказ, клиент: клиент, ядро: ядро) }
    try await доставить(сообщениеПримера(101, тип: "messageText", ожидает: true), клиент: клиент, ядро: ядро, запрос: запрос)
    let события = порядок == "ранний-отказ" ? [отказ] : (порядок == "успех-отказ" ? [успех, отказ, успех] : [отказ, успех, отказ])
    for событие in события { try await доставить(событие, клиент: клиент, ядро: ядро) }
    let результат = try #require(await ядро.получитьПопытки().first { $0.идентификатор == номер })
    #expect(результат.состояние == (порядок == "ранний-отказ" ? .отказ : .требуетсяРазбор))
    #expect(результат.противоречие == (порядок != "ранний-отказ"))
    #expect(результат.сообщения[0].ошибка == 429)
    #expect(await ядро.модель.сообщения[ИдентичностьСообщения(аккаунт: 17, чат: -100001, сообщение: 101)] == nil)
    await ядро.закрытьЖурнал()
    let новыйТранспорт = ЗаписывающийТранспорт()
    let восстановленное = try ЯдроКлиента(транспорт: новыйТранспорт, корень: каталог, ключ: ключ)
    #expect(await восстановленное.получитьПопытки().first { $0.идентификатор == номер } == результат)
    #expect(новыйТранспорт.отправленные.isEmpty)
    await восстановленное.закрытьЖурнал()
}

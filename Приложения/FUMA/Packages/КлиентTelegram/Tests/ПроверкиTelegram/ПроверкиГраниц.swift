@Test func раннийУспехУбираетВременноеСообщениеАПротиворечиеНеГаситсяПовтором() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: Data(repeating: 6, count: 32))
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Точные байты"), цель: "Ранний исход")
    try await ядро.сохранитьЧерновик(черновик)
    let попытка = try await ядро.выполнить(клиент, черновик: черновик.идентификатор, разрешение: РазрешениеДействия(черновик: черновик, основание: "Открытая фикстура"))
    try await провестиПроверкуЧата(ядро, клиент: клиент, транспорт: транспорт)
    let отправка = транспорт.отправленные.last!.1
    let успех = ЗначениеДанных.типа("updateMessageSendSucceeded", ["old_message_id": .число(101), "message": сообщениеПримера(10001, тип: "messageText")])
    try await доставить(успех, клиент: клиент, ядро: ядро)
    try await доставить(сообщениеПримера(101, тип: "messageText", ожидает: true), клиент: клиент, ядро: ядро, запрос: отправка)
    #expect(await ядро.получитьМодельСообщений().сообщения[ИдентичностьСообщения(аккаунт: 17, чат: -100001, сообщение: 101)] == nil)
    #expect(await ядро.получитьПопытки().first { $0.идентификатор == попытка }?.состояние == .выполнено)
    try await доставить(успех.добавив("message", сообщениеПримера(10002, тип: "messageText")), клиент: клиент, ядро: ядро)
    try await доставить(успех, клиент: клиент, ядро: ядро)
    #expect(await ядро.получитьПопытки().first { $0.идентификатор == попытка }?.состояние == .требуетсяРазбор)
    await ядро.закрытьЖурнал()
}

@Test func сохранённоеДоказательствоМеждуДвумяЗаписямиПрименяетсяПриВосстановлении() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let ключ = Data(repeating: 6, count: 32)
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Точные байты"), цель: "Разрыв записи результата")
    var попытка = try Попытка(черновик: черновик, разрешение: РазрешениеДействия(черновик: черновик, основание: "Открытая фикстура"), запрос: .типа("sendMessage"))
    попытка.сообщения = [ИсходСообщения(временный: 101)]; попытка.состояние = .ожидает
    let журнал = try ЛокальныйЖурнал(корень: каталог, ключ: ключ)
    try журнал.добавить(.попытка(попытка))
    try журнал.добавить(.наблюдение(аккаунт: 17, событие: .типа("updateMessageSendSucceeded", [
        "old_message_id": .число(101), "message": сообщениеПримера(10001, тип: "messageText")])))
    журнал.закрыть()
    let ядро = try ЯдроКлиента(транспорт: ЗаписывающийТранспорт(), корень: каталог, ключ: ключ)
    #expect(await ядро.получитьПопытки().first?.состояние == .выполнено)
    #expect(await ядро.получитьПопытки().first?.сообщения.first?.окончательный == 10001)
    await ядро.закрытьЖурнал()
}


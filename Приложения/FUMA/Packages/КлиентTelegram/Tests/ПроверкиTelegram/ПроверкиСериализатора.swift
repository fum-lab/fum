@Test func шестьГруппПроверяютАдресатаПраваИДанныеДоОтправки() throws {
    let файл = Вложение(имя: "пример.txt", данные: Data("Открытая фикстура".utf8))
    let действия: [(ДействиеКанала, String)] = [
        (.текст("Публикация"), "sendMessage"), (.документ(файл, "Подпись"), "sendMessage"),
        (.альбом([файл, файл], "Подпись"), "sendMessageAlbum"),
        (.изменитьТекст(1048576, "Исправление"), "editMessageText"),
        (.изменитьПодпись(1048576, nil), "editMessageCaption"),
        (.изменитьМедиа(1048576, файл, "Замена"), "editMessageMedia")
    ]
    let права = ДопускКанала(аккаунт: 17, канал: -100001, готов: true, подтверждёнАккаунт: true,
        каналПодтверждён: true, можетПисать: true, цельПравки: 1048576,
        можетПравить: true, можетЗаменятьМедиа: true, типМедиа: "messageDocument")
    for (действие, тип) in действия {
        let черновик = Черновик(аккаунт: 17, канал: -100001, действие: действие, цель: "Синтетическая проверка")
        var применимыеПрава = права
        if case .изменитьТекст = действие { применимыеПрава.типМедиа = "messageText" }
        let запрос = try Сериализатор.подготовить(черновик, допуск: применимыеПрава, каталог: "/private/пример")
        #expect(запрос.тип == тип)
        #expect(запрос["chat_id"]?.целое == -100001)
        var безПрав = права; безПрав.можетПисать = false; безПрав.можетПравить = false; безПрав.можетЗаменятьМедиа = false
        #expect(throws: ОшибкаКлиента.self) { try Сериализатор.подготовить(черновик, допуск: безПрав, каталог: "/private/пример") }
        var чужой = права; чужой.аккаунт = 18
        #expect(throws: ОшибкаКлиента.self) { try Сериализатор.подготовить(черновик, допуск: чужой, каталог: "/private/пример") }
        var закрытый = права; закрытый.готов = false
        #expect(throws: ОшибкаКлиента.self) { try Сериализатор.подготовить(черновик, допуск: закрытый, каталог: "/private/пример") }
    }
    let неверные: [ДействиеКанала] = [.текст(""), .документ(Вложение(имя: "../секрет", данные: Data([1])), nil),
        .альбом([файл], nil), .изменитьТекст(0, "текст"), .изменитьПодпись(0, ""),
        .изменитьМедиа(1048576, Вложение(имя: "пусто", данные: Data()), nil), .неподдерживаемое("pinChatMessage")]
    for действие in неверные {
        let черновик = Черновик(аккаунт: 17, канал: -100001, действие: действие, цель: "Проверка отказа")
        #expect(throws: ОшибкаКлиента.self) { try Сериализатор.подготовить(черновик, допуск: права, каталог: "/private/пример") }
    }
    let документ = Черновик(аккаунт: 17, канал: -100001, действие: .документ(файл, nil), цель: "Проверка формы")
    let запрос = try Сериализатор.подготовить(документ, допуск: права, каталог: "/private/пример")
    #expect(запрос["input_message_content"]?["document"]?["@type"]?.строка == "inputDocument")
    #expect(запрос["input_message_content"]?["document"]?["document"]?["@type"]?.строка == "inputFileLocal")
    var тема = документ; тема.тема = .типа("messageTopicForum", ["forum_topic_id": .число(1)])
    #expect(throws: ОшибкаКлиента.неподдерживаемоеДействие) { try Сериализатор.подготовить(тема, допуск: права, каталог: "/private/пример") }
}

@Test func пределыСодержимогоСчитаютКодовыеЕдиницыИСуммуВложений() throws {
    func проверить(_ действие: ДействиеКанала) throws {
        try Сериализатор.проверитьСодержимое(Черновик(аккаунт: 17, канал: -100001, действие: действие, цель: "Границы синтетики"))
    }
    let текст = String(repeating: "🙂", count: 2048)
    try проверить(.текст(текст))
    #expect(throws: ОшибкаКлиента.self) { try проверить(.текст(текст + "a")) }
    try проверить(.изменитьТекст(1048576, текст))
    #expect(throws: ОшибкаКлиента.self) { try проверить(.изменитьТекст(1048576, текст + "a")) }
    let маленький = Вложение(имя: "пример.txt", данные: Data([1]))
    let подпись = String(repeating: "🙂", count: 512)
    for допустимое: ДействиеКанала in [.документ(маленький, подпись), .изменитьПодпись(1048576, подпись), .изменитьМедиа(1048576, маленький, подпись), .альбом(Array(repeating: маленький, count: 10), подпись)] {
        try проверить(допустимое)
    }
    for неверное: ДействиеКанала in [.документ(маленький, подпись + "a"), .изменитьПодпись(1048576, подпись + "a"), .изменитьМедиа(1048576, маленький, подпись + "a"), .альбом(Array(repeating: маленький, count: 11), nil)] {
        #expect(throws: ОшибкаКлиента.self) { try проверить(неверное) }
    }
    try проверить(.изменитьПодпись(1048576, ""))
    try проверить(.изменитьПодпись(1048576, nil))
    let половина = Вложение(имя: "половина", данные: Data(repeating: 1, count: 8 * 1024 * 1024))
    try проверить(.альбом([половина, половина], nil))
    #expect(throws: ОшибкаКлиента.self) { try проверить(.альбом([половина, половина, маленький], nil)) }
}

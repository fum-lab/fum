private func позицияЧата(_ список: String, порядок: String) -> ЗначениеДанных {
    .типа("chatPosition", ["list": .типа(список), "order": .текст(порядок), "is_pinned": .флаг(false), "source": .пусто])
}

@Test func страницыИсторииСохраняютГраницыПовторыИРаздельныеОтветы() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: Data(repeating: 47, count: 32))
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    var корреляции: [String] = []
    let страницы: [(Int64, Int32, Int32, Bool, [ЗначениеДанных])] = [
        (0, 0, 100, true, [сообщениеПримера(1048576, тип: "messageText"), .пусто]),
        (1048576, -2, 2, false, [сообщениеПримера(2097152, тип: "messageText"), сообщениеПримера(1048576, тип: "messageText")])
    ]
    for (от, смещение, предел, местная, сообщения) in страницы {
        let корреляция = try await ядро.прочитатьИсторию(клиент, чат: -100001, от: от, смещение: смещение, предел: предел, толькоМестная: местная)
        корреляции.append(корреляция)
        let запрос = транспорт.отправленные.last!.1
        #expect(try запрос == ЗначениеДанных.типа("getChatHistory", ["chat_id": .число(-100001), "from_message_id": .число(от),
            "offset": .число(Int64(смещение)), "limit": .число(Int64(предел)), "only_local": .флаг(местная)]).добавив("@extra", .текст(корреляция)))
        let ответ = ЗначениеДанных.типа("messages", ["total_count": .число(0), "messages": .массив(сообщения)])
        try await доставить(ответ, клиент: клиент, ядро: ядро, запрос: запрос)
        #expect(try await ядро.взятьОтвет(корреляция, клиент: клиент)?["messages"] == .массив(сообщения))
        try await доставить(ответ, клиент: клиент, ядро: ядро, запрос: запрос)
    }
    #expect(Set(корреляции).count == 2)
    let модель = await ядро.получитьМодельСообщений()
    #expect(модель.история.count == 2)
    #expect(модель.сообщения.count == 2)
    #expect(модель.сообщения.keys.allSatisfy { $0.аккаунт == 17 && $0.чат == -100001 })
    let до = транспорт.отправленные.count
    let неверные: [(Int64, Int32, Int32)] = [(-1, 0, 1), (0, -2, 1), (0, -100, 100), (0, 1, 100), (0, 0, 0), (0, 0, 101)]
    for (от, смещение, предел) in неверные {
        await #expect(throws: ОшибкаКлиента.self) { try await ядро.прочитатьИсторию(клиент, чат: -100001, от: от, смещение: смещение, предел: предел) }
    }
    #expect(транспорт.отправленные.count == до)
    await ядро.закрытьЖурнал()
}

@Test func чужаяКорреляцияИСмешаннаяСтраницаНеЗагрязняютИсторию() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: Data(repeating: 48, count: 32))
    let первый = try await готовыйКлиент(ядро, транспорт: транспорт)
    let второй = try await ядро.добавитьКлиента()
    let корреляция = try await ядро.прочитатьИсторию(первый, чат: -100001)
    let запрос = транспорт.отправленные.last!.1
    let сообщение = сообщениеПримера(1048576, тип: "messageText")
    let ответ = ЗначениеДанных.типа("messages", ["total_count": .число(1), "messages": .массив([сообщение])])
    await #expect(throws: ОшибкаКлиента.self) { try await доставить(ответ, клиент: второй, ядро: ядро, запрос: запрос) }
    #expect(await ядро.получитьМодельСообщений().история.isEmpty)
    let смешанный = try ответ.добавив("messages", .массив([сообщение, сообщение.добавив("chat_id", .число(-100002))]))
    await #expect(throws: ОшибкаКлиента.self) { try await доставить(смешанный, клиент: первый, ядро: ядро, запрос: запрос) }
    #expect(await ядро.получитьМодельСообщений().сообщения.isEmpty)
    #expect(try await ядро.взятьОтвет(корреляция, клиент: первый) == nil)
    try await доставить(ответ, клиент: первый, ядро: ядро, запрос: запрос)
    await #expect(throws: ОшибкаКлиента.self) { try await ядро.взятьОтвет(корреляция, клиент: второй) }
    #expect(try await ядро.взятьОтвет(корреляция, клиент: первый)?.тип == "messages")
    try await доставить(ответ, клиент: первый, ядро: ядро, запрос: запрос)
    #expect(await ядро.получитьМодельСообщений().история.count == 1)
    #expect(try await ядро.состояние(первый).коррелированныхОтветов == 2)
    #expect(try await ядро.состояние(второй).коррелированныхОтветов == 0)
    await ядро.закрытьЖурнал()
}

@Test func списокЧатовПрименяетВсеТриИсточникаПозиций() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: Data(repeating: 46, count: 32))
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let другой = try await ядро.добавитьКлиента()
    let местный = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Местный черновик"), цель: "Независимый предпросмотр")
    try await ядро.сохранитьЧерновик(местный)
    let корреляция = try await ядро.загрузитьЧаты(клиент)
    let загрузка = транспорт.отправленные.last!.1
    #expect(try загрузка == ЗначениеДанных.типа("loadChats", ["chat_list": .типа("chatListMain"), "limit": .число(100)]).добавив("@extra", .текст(корреляция)))
    try await доставить(.типа("ok"), клиент: клиент, ядро: ядро, запрос: загрузка)
    #expect(try await ядро.состояние(клиент).списокЧатовЗагружен == false)
    let главная = позицияЧата("chatListMain", порядок: "9000000000000000000")
    let архивная = позицияЧата("chatListArchive", порядок: "300")
    let чат = ЗначениеДанных.типа("chat", ["id": .число(-100001), "positions": .массив([главная, архивная]), "last_message": .пусто, "draft_message": .пусто])
    try await доставить(.типа("updateNewChat", ["chat": чат]), клиент: клиент, ядро: ядро)
    let новая = позицияЧата("chatListMain", порядок: "9000000000000000001")
    try await доставить(.типа("updateChatPosition", ["chat_id": .число(-100001), "position": новая]), клиент: клиент, ядро: ядро)
    #expect(try await ядро.состояние(клиент).чаты[-100001]?["positions"]?.элементы == [архивная, новая])
    let последнее = сообщениеПримера(1048576, тип: "messageText")
    try await доставить(.типа("updateChatLastMessage", ["chat_id": .число(-100001), "last_message": последнее, "positions": .массив([главная])]), клиент: клиент, ядро: ядро)
    #expect(try await ядро.состояние(клиент).чаты[-100001]?["positions"] == .массив([главная]))
    #expect(try await ядро.состояние(клиент).чаты[-100001]?["last_message"] == последнее)
    let серверный = ЗначениеДанных.типа("draftMessage", ["date": .число(1), "input_message_text": .типа("inputMessageText", [
        "text": .типа("formattedText", ["text": .текст("Серверный черновик"), "entities": .массив([])])])])
    try await доставить(.типа("updateChatDraftMessage", ["chat_id": .число(-100001), "draft_message": серверный, "positions": .массив([архивная])]), клиент: клиент, ядро: ядро)
    #expect(try await ядро.состояние(клиент).чаты[-100001]?["positions"] == .массив([архивная]))
    #expect(try await ядро.состояние(клиент).чаты[-100001]?["draft_message"] == серверный)
    #expect(try await ядро.предпросмотр(местный.идентификатор) == местный)
    try await доставить(.типа("updateChatPosition", ["chat_id": .число(-100001), "position": позицияЧата("chatListArchive", порядок: "0")]), клиент: клиент, ядро: ядро)
    #expect(try await ядро.состояние(клиент).чаты[-100001]?["positions"] == .массив([]))
    #expect(try await ядро.состояние(клиент).чаты[-100001] != nil)
    try await доставить(.типа("updateChatLastMessage", ["chat_id": .число(-100001), "last_message": .пусто, "positions": .массив([])]), клиент: клиент, ядро: ядро)
    try await доставить(.типа("updateChatDraftMessage", ["chat_id": .число(-100001), "draft_message": .пусто, "positions": .массив([])]), клиент: клиент, ядро: ядро)
    #expect(try await ядро.состояние(клиент).чаты[-100001]?["last_message"] == .пусто)
    #expect(try await ядро.состояние(клиент).чаты[-100001]?["draft_message"] == .пусто)
    _ = try await ядро.загрузитьЧаты(клиент, предел: 1)
    try await доставить(.типа("error", ["code": .число(404), "message": .текст("No more chats")]), клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    #expect(try await ядро.состояние(клиент).списокЧатовЗагружен)
    #expect(try await ядро.состояние(другой).списокЧатовЗагружен == false)
    #expect(try await ядро.состояние(другой).чаты.isEmpty)
    #expect(!транспорт.отправленные.contains { $0.1.тип == "setChatDraftMessage" })
    await ядро.закрытьЖурнал()
}

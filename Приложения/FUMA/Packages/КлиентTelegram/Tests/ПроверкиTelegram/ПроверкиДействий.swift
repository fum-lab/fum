@testable import КлиентTelegram

func готовыйКлиент(_ ядро: ЯдроКлиента, транспорт: ЗаписывающийТранспорт) async throws -> Int32 {
    let клиент = try await ядро.добавитьКлиента(аккаунт: 17)
    try await доставить(.типа("updateAuthorizationState", ["authorization_state": .типа("authorizationStateReady")]), клиент: клиент, ядро: ядро)
    try await доставить(.типа("user", ["id": .число(17)]), клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    return клиент
}
func сообщениеПримера(_ номер: Int64, тип: String, ожидает: Bool = false) -> ЗначениеДанных {
    .типа("message", ["id": .число(номер), "chat_id": .число(-100001), "content": .типа(тип),
        "sending_state": ожидает ? .типа("messageSendingStatePending", ["sending_id": .число(1)]) : .пусто])
}
func группаПримера(разрешено: Bool = true) -> ЗначениеДанных {
    .типа("supergroup", ["id": .число(51), "is_channel": .флаг(true), "status": .типа("chatMemberStatusAdministrator", [
        "rights": .типа("chatAdministratorRights", ["can_post_messages": .флаг(разрешено)])])])
}
func провестиПроверкуЧата(_ ядро: ЯдроКлиента, клиент: Int32, транспорт: ЗаписывающийТранспорт) async throws {
    #expect(транспорт.отправленные.last?.1.тип == "getChat")
    try await доставить(.типа("chat", ["id": .число(-100001),
        "type": .типа("chatTypeSupergroup", ["supergroup_id": .число(51), "is_channel": .флаг(true)])]),
        клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    #expect(транспорт.отправленные.last?.1.тип == "getSupergroup")
    try await доставить(группаПримера(), клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
}

@Test func продукционныйПутьШестиОперацийИСохранённыеИсходы() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: Data(repeating: 3, count: 32))
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let файл = Вложение(имя: "проверка.txt", данные: Data("Точные байты синтетики".utf8))
    let действия: [ДействиеКанала] = [.текст("Текст"), .документ(файл, "Подпись"), .альбом([файл, файл], nil),
        .изменитьТекст(1048576, "Правка"), .изменитьПодпись(1048576, "Правка подписи"), .изменитьМедиа(1048576, файл, nil)]
    for (номер, действие) in действия.enumerated() {
        let черновик = Черновик(аккаунт: 17, канал: -100001, действие: действие, цель: "Синтетическая проверка")
        try await ядро.сохранитьЧерновик(черновик)
        let разрешение = try РазрешениеДействия(черновик: черновик, основание: "Точное действие этой открытой фикстуры")
        let попытка = try await ядро.выполнить(клиент, черновик: черновик.идентификатор, разрешение: разрешение)
        try await провестиПроверкуЧата(ядро, клиент: клиент, транспорт: транспорт)
        if действие.сообщение != nil {
            #expect(транспорт.отправленные.last?.1.тип == "getMessage")
            try await доставить(сообщениеПримера(1048576, тип: номер == 3 ? "messageText" : "messageDocument"),
                клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
            #expect(транспорт.отправленные.last?.1.тип == "getMessageProperties")
            try await доставить(.типа("messageProperties", ["can_be_edited": .флаг(true), "can_edit_media": .флаг(true)]),
                клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
        }
        let запрос = транспорт.отправленные.last!.1
        #expect(await ядро.получитьПопытки().first { $0.идентификатор == попытка }?.состояние == .передОтправкой)
        if номер == 2 {
            try await доставить(.типа("messages", ["total_count": .число(2), "messages": .массив([
                сообщениеПримера(110, тип: "messageDocument", ожидает: true), сообщениеПримера(111, тип: "messageDocument", ожидает: true)])]),
                клиент: клиент, ядро: ядро, запрос: запрос)
            for временный: Int64 in [110, 111] {
                try await доставить(.типа("updateMessageSendSucceeded", ["old_message_id": .число(временный),
                    "message": сообщениеПримера(временный + 10000, тип: "messageDocument")]), клиент: клиент, ядро: ядро)
            }
        } else if номер < 2 {
            let временный = Int64(101 + номер)
            try await доставить(сообщениеПримера(временный, тип: номер == 0 ? "messageText" : "messageDocument", ожидает: true),
                клиент: клиент, ядро: ядро, запрос: запрос)
            #expect(await ядро.получитьПопытки().first { $0.идентификатор == попытка }?.состояние == .ожидает)
            try await доставить(.типа("updateMessageSendSucceeded", ["old_message_id": .число(временный),
                "message": сообщениеПримера(временный + 10000, тип: номер == 0 ? "messageText" : "messageDocument")]), клиент: клиент, ядро: ядро)
        } else {
            try await доставить(сообщениеПримера(1048576, тип: номер == 3 ? "messageText" : "messageDocument"), клиент: клиент, ядро: ядро, запрос: запрос)
        }
        #expect(await ядро.получитьПопытки().first { $0.идентификатор == попытка }?.состояние == .выполнено)
        await #expect(throws: ОшибкаКлиента.self) {
            try await ядро.выполнить(клиент, черновик: черновик.идентификатор, разрешение: разрешение)
        }
    }
    await ядро.закрытьЖурнал()
    let восстановленное = try ЯдроКлиента(транспорт: ЗаписывающийТранспорт(), корень: каталог, ключ: Data(repeating: 3, count: 32))
    #expect(await восстановленное.получитьПопытки().count == 6)
    #expect(await восстановленное.получитьПопытки().allSatisfy { $0.состояние == .выполнено })
    await восстановленное.закрытьЖурнал()
}

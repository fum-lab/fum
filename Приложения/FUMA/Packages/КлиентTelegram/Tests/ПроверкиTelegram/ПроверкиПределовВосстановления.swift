import Testing
@testable import КлиентTelegram

private final class ЗапрещённыйТранспортВосстановления: ТранспортБиблиотеки {
    func создатьКлиента() -> Int32 { Issue.record("Восстановление вызвало create"); return 1 }
    func отправить(клиент: Int32, запрос: Data) throws { Issue.record("Восстановление вызвало send") }
    func принять(таймАут: Double) throws -> Data? { Issue.record("Восстановление вызвало receive"); return nil }
}

private func записьПредела(попытка: Bool) throws -> ЛокальнаяЗапись {
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Открытая фикстура"), цель: "Предел восстановления")
    if попытка {
        return .попытка(try Попытка(черновик: черновик,
            разрешение: РазрешениеДействия(черновик: черновик, основание: "Синтетический допуск"), запрос: .типа("sendMessage")))
    }
    return .черновик(черновик)
}

@Test(arguments: [false, true])
func восстановлениеРазличаетПределСущностейИПовторы(попытка: Bool) async throws {
    let каталог = try создатьПриватныйКаталог()
    defer { try? FileManager.default.removeItem(at: каталог) }
    let ключ = Data(repeating: 61, count: 32)
    let первый = try записьПредела(попытка: попытка)
    let журнал = try ЛокальныйЖурнал(корень: каталог, ключ: ключ)
    try журнал.добавить(первый)
    for _ in 1..<256 { try журнал.добавить(записьПредела(попытка: попытка)) }
    try журнал.добавить(первый)
    try журнал.добавить(первый)
    журнал.закрыть()
    let ядро = try ЯдроКлиента(транспорт: ЗапрещённыйТранспортВосстановления(), корень: каталог, ключ: ключ)
    if попытка { #expect(await ядро.попытки.count == 256) }
    else { #expect(await ядро.черновики.count == 256) }
    await ядро.закрытьЖурнал()

    let дополнение = try ЛокальныйЖурнал(корень: каталог, ключ: ключ)
    try дополнение.добавить(записьПредела(попытка: попытка))
    дополнение.закрыть()
    let путь = каталог.appendingPathComponent("сегмент.fumobs")
    let до = try Data(contentsOf: путь)
    var отклонён = false
    do {
        let лишнее = try ЯдроКлиента(транспорт: ЗапрещённыйТранспортВосстановления(), корень: каталог, ключ: ключ)
        await лишнее.закрытьЖурнал()
    } catch {
        #expect(error as? ОшибкаКлиента == .превышенПредел)
        отклонён = true
    }
    #expect(отклонён)
    #expect(try Data(contentsOf: путь) == до)
    let повтор = try ЛокальныйЖурнал(корень: каталог, ключ: ключ)
    повтор.закрыть()
}

@Test func восстановлениеОтклоняетИзменённыйЧерновикСТемЖеНомером() async throws {
    let каталог = try создатьПриватныйКаталог()
    defer { try? FileManager.default.removeItem(at: каталог) }
    let ключ = Data(repeating: 62, count: 32)
    let первый = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Первый"), цель: "Неизменяемый черновик")
    let второй = Черновик(идентификатор: первый.идентификатор, аккаунт: 17, канал: -100001,
        действие: .текст("Изменённый"), цель: первый.цель)
    let журнал = try ЛокальныйЖурнал(корень: каталог, ключ: ключ)
    try журнал.добавить(.черновик(первый))
    try журнал.добавить(.черновик(второй))
    журнал.закрыть()
    var отклонён = false
    do {
        let ядро = try ЯдроКлиента(транспорт: ЗапрещённыйТранспортВосстановления(), корень: каталог, ключ: ключ)
        await ядро.закрытьЖурнал()
    } catch {
        #expect(error as? ОшибкаКлиента == .доступЗапрещён("Изменённому черновику нужен новый идентификатор"))
        отклонён = true
    }
    #expect(отклонён)
}

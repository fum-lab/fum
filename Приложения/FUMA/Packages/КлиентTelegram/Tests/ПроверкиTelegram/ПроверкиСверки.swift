import Foundation
import Testing
@testable import КлиентTelegram

@Test func публичнаяСверкаНеЗаменяетДоказательствоИНеПовторяетОтправку() async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let ключ = Data(repeating: 49, count: 32)
    let первыйТранспорт = ЗаписывающийТранспорт()
    let первое = try ЯдроКлиента(транспорт: первыйТранспорт, корень: каталог, ключ: ключ)
    let первый = try await готовыйКлиент(первое, транспорт: первыйТранспорт)
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: .текст("Совпадающий текст"), цель: "Сверка после перезапуска")
    try await первое.сохранитьЧерновик(черновик)
    let попытка = try await первое.выполнить(первый, черновик: черновик.идентификатор,
        разрешение: РазрешениеДействия(черновик: черновик, основание: "Синтетическая попытка"))
    try await провестиПроверкуЧата(первое, клиент: первый, транспорт: первыйТранспорт)
    try await доставить(сообщениеПримера(101, тип: "messageText", ожидает: true), клиент: первый, ядро: первое, запрос: первыйТранспорт.отправленные.last!.1)
    await первое.закрытьЖурнал()

    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: ключ)
    #expect(транспорт.отправленные.isEmpty)
    #expect(await ядро.получитьПопытки().first?.состояние == .требуетсяРазбор)
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let другой = try await ядро.добавитьКлиента(аккаунт: 18)
    try await доставить(.типа("updateAuthorizationState", ["authorization_state": .типа("authorizationStateReady")]), клиент: другой, ядро: ядро)
    try await доставить(.типа("user", ["id": .число(18)]), клиент: другой, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    let до = транспорт.отправленные.count
    await #expect(throws: ОшибкаКлиента.self) { try await ядро.сверить(другой, попытка: попытка) }
    await #expect(throws: ОшибкаКлиента.self) { try await ядро.сверить(клиент, попытка: UUID()) }
    #expect(транспорт.отправленные.count == до)

    let похожее = try сообщениеПримера(90001, тип: "messageText").добавив("content", .типа("messageText", [
        "text": .типа("formattedText", ["text": .текст("Совпадающий текст"), "entities": .массив([])])]))
    for местная in [true, false] {
        let корреляция = try await ядро.сверить(клиент, попытка: попытка, от: местная ? 0 : 1048576, толькоМестная: местная)
        let запрос = транспорт.отправленные.last!.1
        #expect(try запрос == ЗначениеДанных.типа("getChatHistory", ["chat_id": .число(-100001), "from_message_id": .число(местная ? 0 : 1048576),
            "offset": .число(0), "limit": .число(100), "only_local": .флаг(местная)]).добавив("@extra", .текст(корреляция)))
        let чужое = try похожее.добавив("chat_id", .число(-100002))
        await #expect(throws: ОшибкаКлиента.self) {
            try await доставить(.типа("messages", ["total_count": .число(1), "messages": .массив([чужое])]), клиент: клиент, ядро: ядро, запрос: запрос)
        }
        #expect(await ядро.получитьПопытки().first?.состояние == .требуетсяРазбор)
        try await доставить(.типа("messages", ["total_count": .число(местная ? 0 : 1), "messages": .массив(местная ? [] : [похожее])]),
            клиент: клиент, ядро: ядро, запрос: запрос)
        #expect(await ядро.получитьПопытки().first?.состояние == .требуетсяРазбор)
    }
    let успех = ЗначениеДанных.типа("updateMessageSendSucceeded", ["old_message_id": .число(101), "message": сообщениеПримера(10001, тип: "messageText")])
    try await доставить(успех, клиент: другой, ядро: ядро)
    try await доставить(успех.добавив("message", сообщениеПримера(10001, тип: "messageText").добавив("chat_id", .число(-100002))), клиент: клиент, ядро: ядро)
    try await доставить(успех.добавив("old_message_id", .число(102)), клиент: клиент, ядро: ядро)
    #expect(await ядро.получитьПопытки().first?.состояние == .требуетсяРазбор)
    try await доставить(успех, клиент: клиент, ядро: ядро)
    try await доставить(успех, клиент: клиент, ядро: ядро)
    #expect(await ядро.получитьПопытки().first?.состояние == .выполнено)
    #expect(await ядро.получитьПопытки().first?.сообщения.first?.окончательный == 10001)
    #expect(!транспорт.отправленные.contains { $0.1.тип?.hasPrefix("send") == true || $0.1.тип?.hasPrefix("edit") == true })
    await ядро.закрытьЖурнал()
    let последнийТранспорт = ЗаписывающийТранспорт()
    let восстановленное = try ЯдроКлиента(транспорт: последнийТранспорт, корень: каталог, ключ: ключ)
    #expect(await восстановленное.получитьПопытки().first?.состояние == .выполнено)
    #expect(await восстановленное.получитьПопытки().first?.сообщения.first?.окончательный == 10001)
    #expect(последнийТранспорт.отправленные.isEmpty)
    await восстановленное.закрытьЖурнал()
}

private func действиеДляПроверкиПрав(_ номер: Int) -> ДействиеКанала {
    let файл = Вложение(имя: "синтетика.txt", данные: Data([1, 2, 3]))
    return [.текст("Текст"), .документ(файл, "Подпись"), .альбом([файл, файл], nil),
            .изменитьТекст(1048576, "Правка"), .изменитьПодпись(1048576, nil), .изменитьМедиа(1048576, файл, nil)][номер]
}

private func чатДляПроверкиПрав() -> ЗначениеДанных {
    .типа("chat", ["id": .число(-100001),
        "type": .типа("chatTypeSupergroup", ["supergroup_id": .число(51), "is_channel": .флаг(true)])])
}

private func начатьПроверкуПрав(_ ядро: ЯдроКлиента, клиент: Int32, действие: ДействиеКанала) async throws -> UUID {
    let черновик = Черновик(аккаунт: 17, канал: -100001, действие: действие, цель: "Отказ до отправки")
    try await ядро.сохранитьЧерновик(черновик)
    return try await ядро.выполнить(клиент, черновик: черновик.идентификатор,
        разрешение: РазрешениеДействия(черновик: черновик, основание: "Только синтетическая проверка"))
}

private func проверитьОтсутствиеИсходящегоДействия(_ транспорт: ЗаписывающийТранспорт) {
    let типы = транспорт.отправленные.compactMap { $0.1.тип }
    #expect(!типы.contains { ["sendMessage", "sendMessageAlbum", "editMessageText", "editMessageCaption", "editMessageMedia"].contains($0) })
}

@Test(arguments: 0...5, [false, true])
func ядроОтклоняетШестьОперацийБезСтатусаИПрименимогоПрава(_ номер: Int, _ нетСтатуса: Bool) async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: Data(repeating: 43, count: 32))
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let попытка = try await начатьПроверкуПрав(ядро, клиент: клиент, действие: действиеДляПроверкиПрав(номер))
    try await доставить(чатДляПроверкиПрав(), клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    let группа = нетСтатуса ? try группаПримера().добавив("status", .типа("chatMemberStatusMember")) : группаПримера(разрешено: номер >= 3)
    try await доставить(группа, клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    if номер >= 3 {
        #expect(транспорт.отправленные.last?.1.тип == "getMessage")
        try await доставить(сообщениеПримера(1048576, тип: номер == 3 ? "messageText" : "messageDocument"),
            клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
        #expect(транспорт.отправленные.last?.1.тип == "getMessageProperties")
        // У каждой правки отозвано только применимое право; второе оставлено истинным.
        try await доставить(.типа("messageProperties", ["can_be_edited": .флаг(нетСтатуса || номер == 5),
            "can_edit_media": .флаг(нетСтатуса || номер != 5)]), клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    }
    #expect(await ядро.взятьОтказПодготовки(попытка) != nil)
    #expect(await ядро.получитьПопытки().isEmpty)
    проверитьОтсутствиеИсходящегоДействия(транспорт)
    await ядро.закрытьЖурнал()
}

@Test(arguments: [0, 5], ["updateSupergroup", "authorizationStateLoggingOut", "authorizationStateClosing"])
func отзывВоВремяПроверкиЗапрещаетПозднееПоложительноеРешение(_ номер: Int, _ отзыв: String) async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: Data(repeating: 44, count: 32))
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    let попытка = try await начатьПроверкуПрав(ядро, клиент: клиент, действие: действиеДляПроверкиПрав(номер))
    try await доставить(чатДляПроверкиПрав(), клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    if номер == 5 {
        try await доставить(группаПримера(), клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
        try await доставить(сообщениеПримера(1048576, тип: "messageDocument"), клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
    }
    let ожидаемыйЗапрос = транспорт.отправленные.last!.1
    #expect(ожидаемыйЗапрос.тип == (номер == 0 ? "getSupergroup" : "getMessageProperties"))
    let событие = отзыв == "updateSupergroup" ? ЗначениеДанных.типа(отзыв, ["supergroup": try группаПримера().добавив("status", .типа("chatMemberStatusMember"))]) :
        .типа("updateAuthorizationState", ["authorization_state": .типа(отзыв)])
    try await доставить(событие, клиент: клиент, ядро: ядро)
    let позднийОтвет = номер == 0 ? группаПримера() : .типа("messageProperties", ["can_be_edited": .флаг(true), "can_edit_media": .флаг(true)])
    try await доставить(позднийОтвет, клиент: клиент, ядро: ядро, запрос: ожидаемыйЗапрос)
    #expect(await ядро.взятьОтказПодготовки(попытка) != nil)
    #expect(await ядро.получитьПопытки().isEmpty)
    проверитьОтсутствиеИсходящегоДействия(транспорт)
    await ядро.закрытьЖурнал()
}

@Test(arguments: ["чужой чат", "не канал", "чужая группа", "чужое сообщение", "неверный тип медиа", "нет подходящего аккаунта"])
func несовпадающаяИдентичностьИТипНеРазрешаютПравку(_ причина: String) async throws {
    let каталог = try создатьПриватныйКаталог(); defer { try? FileManager.default.removeItem(at: каталог) }
    let транспорт = ЗаписывающийТранспорт()
    let ядро = try ЯдроКлиента(транспорт: транспорт, корень: каталог, ключ: Data(repeating: 45, count: 32))
    let клиент = try await готовыйКлиент(ядро, транспорт: транспорт)
    if причина == "нет подходящего аккаунта" {
        let другой = try await ядро.добавитьКлиента(аккаунт: 18)
        try await доставить(.типа("updateAuthorizationState", ["authorization_state": .типа("authorizationStateReady")]), клиент: другой, ядро: ядро)
        try await доставить(.типа("user", ["id": .число(18)]), клиент: другой, ядро: ядро, запрос: транспорт.отправленные.last!.1)
        let до = транспорт.отправленные.count
        await #expect(throws: ОшибкаКлиента.self) { try await начатьПроверкуПрав(ядро, клиент: другой, действие: действиеДляПроверкиПрав(5)) }
        #expect(транспорт.отправленные.count == до)
    } else {
        let попытка = try await начатьПроверкуПрав(ядро, клиент: клиент, действие: действиеДляПроверкиПрав(5))
        var чат = чатДляПроверкиПрав()
        if причина == "чужой чат" { чат = try чат.добавив("id", .число(-100002)) }
        if причина == "не канал" { чат = try чат.добавив("type", .типа("chatTypeSupergroup", ["supergroup_id": .число(51), "is_channel": .флаг(false)])) }
        try await доставить(чат, клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
        if !["чужой чат", "не канал"].contains(причина) {
            #expect(транспорт.отправленные.last?.1.тип == "getSupergroup")
            let группа = причина == "чужая группа" ? try группаПримера().добавив("id", .число(52)) : группаПримера()
            try await доставить(группа, клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
        }
        if ["чужое сообщение", "неверный тип медиа"].contains(причина) {
            #expect(транспорт.отправленные.last?.1.тип == "getMessage")
            let сообщение = сообщениеПримера(причина == "чужое сообщение" ? 2097152 : 1048576, тип: причина == "неверный тип медиа" ? "messagePhoto" : "messageDocument")
            try await доставить(сообщение, клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
        }
        if причина == "неверный тип медиа" {
            #expect(транспорт.отправленные.last?.1.тип == "getMessageProperties")
            try await доставить(.типа("messageProperties", ["can_be_edited": .флаг(true), "can_edit_media": .флаг(true)]),
                клиент: клиент, ядро: ядро, запрос: транспорт.отправленные.last!.1)
        }
        #expect(await ядро.взятьОтказПодготовки(попытка) != nil)
    }
    #expect(await ядро.получитьПопытки().isEmpty)
    проверитьОтсутствиеИсходящегоДействия(транспорт)
    await ядро.закрытьЖурнал()
}

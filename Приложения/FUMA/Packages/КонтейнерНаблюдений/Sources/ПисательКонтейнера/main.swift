import КонтейнерНаблюдений
import Foundation
import Darwin

/// Узкая грамматика закрытого описания: дубликаты проверяются до Codable.
private struct ЧитательОписания {
    let данные: Data
    let байты: [UInt8]
    var позиция = 0

    init(_ данные: Data) { self.данные = данные; байты = Array(данные) }

    mutating func пробелы() {
        while позиция < байты.count && [9, 10, 13, 32].contains(байты[позиция]) { позиция += 1 }
    }

    mutating func знак(_ значение: UInt8) throws {
        пробелы()
        guard позиция < байты.count, байты[позиция] == значение else { throw ОшибкаКонтейнера.повреждение }
        позиция += 1
    }

    mutating func строка() throws -> String {
        пробелы()
        let начало = позиция
        try знак(34)
        while позиция < байты.count {
            let символ = байты[позиция]
            позиция += 1
            if символ == 92 {
                guard позиция < байты.count else { throw ОшибкаКонтейнера.повреждение }
                позиция += 1
            } else if символ == 34 {
                return try JSONDecoder().decode(String.self, from: Data(байты[начало..<позиция]))
            }
        }
        throw ОшибкаКонтейнера.повреждение
    }

    mutating func прочитать() throws -> ОписаниеНаблюдения {
        let поля = ["идентификатор", "тип", "версияСхемы", "источник", "время", "спецификация"]
        let точные = Set(поля.map { Data($0.utf8) })
        var встречены = Set<Data>()
        try знак(123)
        while true {
            пробелы()
            if позиция < байты.count, байты[позиция] == 125 { позиция += 1; break }
            let ключ = try строка(), точныйКлюч = Data(ключ.utf8)
            guard точные.contains(точныйКлюч), встречены.insert(точныйКлюч).inserted else {
                throw ОшибкаКонтейнера.повреждение
            }
            try знак(58)
            if ключ == "версияСхемы" {
                пробелы()
                let начало = позиция
                while позиция < байты.count, (48...57).contains(байты[позиция]) { позиция += 1 }
                guard позиция > начало, байты[начало] != 48,
                      Int(String(decoding: байты[начало..<позиция], as: UTF8.self)) != nil else {
                    throw ОшибкаКонтейнера.повреждение
                }
            } else { _ = try строка() }
            пробелы()
            guard позиция < байты.count else { throw ОшибкаКонтейнера.повреждение }
            if байты[позиция] == 125 { позиция += 1; break }
            try знак(44)
            пробелы()
            guard позиция < байты.count, байты[позиция] != 125 else { throw ОшибкаКонтейнера.повреждение }
        }
        пробелы()
        guard позиция == байты.count, встречены == точные else { throw ОшибкаКонтейнера.повреждение }
        return try JSONDecoder().decode(ОписаниеНаблюдения.self, from: данные)
    }
}

do {
    let аргументы = Array(CommandLine.arguments.dropFirst())
    guard аргументы.count >= 2, аргументы[1].hasPrefix("/") else {
        throw ОшибкаКонтейнера.небезопасныйПуть
    }
    let корень = URL(fileURLWithPath: аргументы[1], isDirectory: true)
    if аргументы[0] == "добавить", аргументы.count == 5 || аргументы.count == 6 {
        let данные = try прочитатьВход(аргументы[4])
        let спецификация = аргументы.count == 6 ? try прочитатьВход(аргументы[5], предел: 65_536) : Data("неинтерпретируемые байты".utf8)
        guard спецификация.count <= 65_536 else { throw ОшибкаКонтейнера.предел }
        let писатель = try Сегмент(кореньДанных: корень, запись: true)
        defer { писатель.закрыть() }
        let описание = ОписаниеНаблюдения(идентификатор: аргументы[2], тип: аргументы[3], спецификация: спецификация)
        try вывестиJSON(писатель.добавить(описание, данные: данные))
    } else if аргументы[0] == "добавить-описание", аргументы.count == 4 {
        var читатель = ЧитательОписания(try прочитатьВход(аргументы[2], предел: 131_072))
        let описание = try читатель.прочитать()
        let данные = try прочитатьВход(аргументы[3], предел: 67_108_864)
        let писатель = try Сегмент(кореньДанных: корень, запись: true)
        defer { писатель.закрыть() }
        try вывестиJSON(писатель.добавить(описание, данные: данные))
    } else if аргументы[0] == "удерживать", аргументы.count == 2 {
        let писатель = try Сегмент(кореньДанных: корень, запись: true)
        defer { писатель.закрыть() }
        try вывестиJSON(["состояние": "замок-удерживается"])
        // Явный барьер для диагностики конкуренции; EOF или байт отпускает замок.
        _ = try FileHandle.standardInput.read(upToCount: 1)
    } else {
        throw ОшибкаКонтейнера.повреждение
    }
} catch {
    try? FileHandle.standardError.write(contentsOf: Data("Писатель: \(error)\n".utf8))
    exit(1)
}

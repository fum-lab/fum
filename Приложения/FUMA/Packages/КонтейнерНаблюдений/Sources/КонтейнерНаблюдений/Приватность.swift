import Darwin

/// Строгий профиль отвергает любое расширенное свойство ACL, включая пустое.
/// Проверяется фактический fd; это не замок от несогласованной смены прав владельцем.
public func проверитьОтсутствиеРасширенныхПрав(_ дескриптор: Int32) throws {
    guard let безопасность = filesec_init() else { throw ОшибкаКонтейнера.небезопасныйПуть }
    defer { filesec_free(безопасность) }
    var сведения = stat()
    var естьРежим: Int32 = 0
    var режим: mode_t = 0
    var естьСписок: Int32 = 0
    // acl_get_fd_np смешивает отсутствие ACL с ошибкой. MODE доказывает заполнение filesec.
    // Первичный контракт: Apple Libc sys/statx_np.c и gen/filesec.c; query возвращает маску.
    guard fstatx_np(дескриптор, &сведения, безопасность) == 0,
          filesec_query_property(безопасность, FILESEC_MODE, &естьРежим) == 0, естьРежим != 0,
          filesec_get_property(безопасность, FILESEC_MODE, &режим) == 0, режим == сведения.st_mode,
          filesec_query_property(безопасность, FILESEC_ACL, &естьСписок) == 0, естьСписок == 0 else {
        throw ОшибкаКонтейнера.небезопасныйПуть
    }
}

func проверитьПриватностьДескриптора(_ дескриптор: Int32, каталог: Bool) throws {
    var сведения = stat()
    guard fstat(дескриптор, &сведения) == 0,
          сведения.st_mode & S_IFMT == (каталог ? S_IFDIR : S_IFREG),
          сведения.st_mode & 0o7777 == (каталог ? 0o700 : 0o600), сведения.st_uid == geteuid(),
          каталог || сведения.st_nlink == 1 else { throw ОшибкаКонтейнера.небезопасныйПуть }
    try проверитьОтсутствиеРасширенныхПрав(дескриптор)
}

    }

    static func перенести(
        по плану: ПланПереносаФайловойСистемы,
        в кореньНазначения: URL,
        прочитатьНазначение: (URL, String) throws -> СнимокФайловойСистемы
    ) throws -> ИтогПереносаФайловойСистемы {
        let актуальный = try наблюдать(корень: плану.кореньИсточника, источник: плану.источник)
        guard актуальный.идентификатор == плану.идентификаторСнимка,
              try хэшировать(СодержимоеСнимка(
                источник: плану.источник,
                записи: плану.записи.map(КраткоеОписание.init))) == плану.хэшПлана else {
            throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
        }
        let физическийПриёмник = try проверитьВременныйКорень(кореньНазначения)
        let приёмник = try открытьКорень(физическийПриёмник)
        defer { _ = Darwin.close(приёмник) }
        let ключПопытки = КлючПопыткиПереносаФайловойСистемы(
            источник: плану.источник,
            снимок: плану.идентификаторСнимка,
            план: плану.хэшПлана,
            назначение: физическийПриёмник.path)
        guard !попыткиПереноса.ужеНачата(ключПопытки) else {
            throw ОшибкаНаблюденияФайловойСистемы.повторПереносаЗапрещён
        }
        guard try перечислитьИмена(приёмник).isEmpty else {
            throw ОшибкаНаблюденияФайловойСистемы.каталогНеПуст
        }
        guard попыткиПереноса.зарегистрировать(ключПопытки) else {
            throw ОшибкаНаблюденияФайловойСистемы.повторПереносаЗапрещён
        }

        var стадия = СтадияНеизвестногоПереносаФайловойСистемы.запись
        for запись in плану.записи {
            do {
                switch запись.тип {
                case .файл:
                    guard let содержимое = запись.содержимое else {
                        throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
                    }
                    try записатьФайл(запись, содержимое: содержимое, в: приёмник)
                case .ссылка:
                    guard let цель = запись.цельСсылки else {
                        throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
                    }
                    try создатьСсылку(имя: запись.путь, цель: цель, в: приёмник)
                }
            } catch let ошибка as ОшибкаНаблюденияФайловойСистемы {
                throw ошибкаПереносаНеизвестна(
                    план: плану, назначение: физическийПриёмник,
                    стадия: стадия, причина: String(describing: ошибка))
            } catch {
                throw ошибкаПереносаНеизвестна(
                    план: плану, назначение: физическийПриёмник,
                    стадия: стадия, причина: String(describing: error))
            }
        }
        стадия = .синхронизацияНазначения
        guard fsync(приёмник) == 0 else {
            throw ошибкаПереносаНеизвестна(
                план: плану, назначение: физическийПриёмник,
                стадия: стадия, причина: "fsync(назначение): errno=\(errno)")
        }

        стадия = .чтениеНазначения
        var прочитанныйСнимок: СнимокФайловойСистемы?
        do {
            let снимокНазначения = try прочитатьНазначение(физическийПриёмник, плану.источник)
            прочитанныйСнимок = снимокНазначения
            guard снимокНазначения.идентификатор == плану.идентификаторСнимка,
                  снимокНазначения.записи == плану.записи else {
                throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
            }
        } catch {
            throw ошибкаПереносаНеизвестна(
                план: плану, назначение: физическийПриёмник,
                стадия: стадия, причина: String(describing: error),
                фактическийСнимок: прочитанныйСнимок)
        }
        guard let снимокНазначения = прочитанныйСнимок else {
            throw ошибкаПереносаНеизвестна(
                план: плану, назначение: физическийПриёмник,
                стадия: стадия, причина: "снимок назначения не получен")
        }
        return ИтогПереносаФайловойСистемы(
            источник: плану.источник,
            идентификаторСнимкаИсточника: плану.идентификаторСнимка,
            хэшСнимкаПриёмника: снимокНазначения.идентификатор,
            количествоЗаписей: снимокНазначения.записи.count,
            проверкаПовтора: 0,
            физическийИсточник: плану.кореньИсточника,
            физическоеНазначение: физическийПриёмник)
    }

    private static func ошибкаПереносаНеизвестна(
        план: ПланПереносаФайловойСистемы,
        назначение: URL,
        стадия: СтадияНеизвестногоПереносаФайловойСистемы,
        причина: String,
        фактическийСнимок: СнимокФайловойСистемы? = nil
    ) -> ОшибкаНаблюденияФайловойСистемы {
        let свидетельство = СвидетельствоНеизвестногоПереносаФайловойСистемы(
            источник: план.источник,
            идентификаторСнимкаИсточника: план.идентификаторСнимка,
            хэшПлана: план.хэшПлана,
            назначение: назначение,
            ожидаемыеЗаписи: план.записи.map(ОжидаемаяЗаписьПереносаФайловойСистемы.init),
            фактическийИдентификаторСнимкаНазначения: фактическийСнимок?.идентификатор,
            фактическиеЗаписиНазначения: фактическийСнимок?.записи.map(ОжидаемаяЗаписьПереносаФайловойСистемы.init),
            стадия: стадия,
            причина: причина)
        return .неизвестныйИсходПереноса(свидетельство)
    }

    public static func проверитьСохранение(
        результата: ИтогПереносаФайловойСистемы,
        источник: URL,
        назначение: URL,
        номерПовтора: Int
    ) throws -> ИтогПереносаФайловойСистемы {
        guard номерПовтора > результата.проверкаПовтора else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let физическийИсточник = try проверитьВременныйКорень(источник)
        let физическоеНазначение = try проверитьВременныйКорень(назначение)
        guard физическийИсточник == результата.физическийИсточник,
              физическоеНазначение == результата.физическоеНазначение else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let снятиеИсточника = try наблюдать(корень: физическийИсточник, источник: результата.источник)
        let снятиеНазначения = try наблюдать(корень: физическоеНазначение, источник: результата.источник)
        guard снятиеИсточника.идентификатор == результата.идентификаторСнимкаИсточника,
              снятиеНазначения.идентификатор == результата.хэшСнимкаПриёмника,
              снятиеИсточника.записи == снятиеНазначения.записи,
              снятиеНазначения.записи.count == результата.количествоЗаписей else {
            throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
        }
        return ИтогПереносаФайловойСистемы(
            источник: результата.источник,
            идентификаторСнимкаИсточника: результата.идентификаторСнимкаИсточника,
            хэшСнимкаПриёмника: результата.хэшСнимкаПриёмника,
            количествоЗаписей: результата.количествоЗаписей,
            проверкаПовтора: номерПовтора,
            физическийИсточник: результата.физическийИсточник,
            физическоеНазначение: результата.физическоеНазначение)
    }


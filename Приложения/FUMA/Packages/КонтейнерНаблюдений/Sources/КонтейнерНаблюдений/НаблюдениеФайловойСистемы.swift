import Foundation
import Darwin
import CryptoKit

public enum ТипЭлементаФайловойСистемы: String, Codable, Sendable {
    case файл
    case ссылка
}

public struct ЗаписьФайловойСистемы: Equatable, Sendable {
    public let путь: String
    public let тип: ТипЭлементаФайловойСистемы
    public let владелец: UInt32
    public let режим: UInt16
    public let размер: UInt64
    public let содержимое: Data?
    public let цельСсылки: String?
    public let хэш: String
}

public struct СнимокФайловойСистемы: Equatable, Sendable {
    public let источник: String
    public let предшественник: String?
    public let записи: [ЗаписьФайловойСистемы]
    public let идентификатор: String
    let физическийКорень: URL
}

public enum ВидИзмененияФайловойСистемы: String, Codable, Sendable {
    case добавлен
    case изменён
    case удалён
}

public struct ИзменениеФайловойСистемы: Equatable, Sendable {
    public let вид: ВидИзмененияФайловойСистемы
    public let путь: String
    public let прежнийХэш: String?
    public let новыйХэш: String?
}

public struct ПланПереносаФайловойСистемы: Equatable, Sendable {
    public let источник: String
    public let идентификаторСнимка: String
    public let записи: [ЗаписьФайловойСистемы]
    public let хэшПлана: String
    let кореньИсточника: URL
}

public struct ИтогПереносаФайловойСистемы: Equatable, Sendable {
    public let источник: String
    public let идентификаторСнимкаИсточника: String
    public let хэшСнимкаПриёмника: String
    public let количествоЗаписей: Int
    public let проверкаПовтора: Int
    let физическийИсточник: URL
    let физическоеНазначение: URL
}

public enum ОшибкаНаблюденияФайловойСистемы: Error, Equatable, Sendable {
    case недопустимыйИсточник
    case неподдержанныйОбъект(String)
    case превышенПредел
    case источникИзменился
    case каталогНеПуст
    case несовпадениеСохранения
    case неизвестныйИсход
    case система(Int32)
}

public enum НаблюдениеФайловойСистемы {
    private static let пределФайла = Пределы.фрагмент
    private static let пределЗаписей = 64
    private static let пределСсылки = 4096
    private static let пределСнимка = Int(Пределы.объект)

    public static func наблюдать(
        корень: URL,
        источник: String,
        предшественник: СнимокФайловойСистемы? = nil
    ) throws -> СнимокФайловойСистемы {
        guard !источник.isEmpty, источник.utf8.count <= 256,
              предшественник == nil || предшественник?.источник == источник else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let физическийКорень = try проверитьВременныйКорень(корень)
        let дескриптор = try открытьКорень(физическийКорень)
        defer { _ = Darwin.close(дескриптор) }

        var исходноеСостояниеКаталога = stat()
        guard fstat(дескриптор, &исходноеСостояниеКаталога) == 0,
              исходноеСостояниеКаталога.st_mode & S_IFMT == S_IFDIR else {
            throw ОшибкаНаблюденияФайловойСистемы.система(errno)
        }
        let имена = try перечислитьИмена(дескриптор)
        guard имена.count <= пределЗаписей else { throw ОшибкаНаблюденияФайловойСистемы.превышенПредел }
        guard Set(имена).count == имена.count else {
            throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("нормализующая-коллизия-имён")
        }
        var записи: [ЗаписьФайловойСистемы] = []
        записи.reserveCapacity(имена.count)
        var оставшийсяБюджет = пределСнимка
        for имя in имена {
            let запись = try снять(дескрипторКорня: дескриптор, имя: имя, пределБайтов: оставшийсяБюджет)
            guard запись.размер <= UInt64(оставшийсяБюджет) else {
                throw ОшибкаНаблюденияФайловойСистемы.превышенПредел
            }
            оставшийсяБюджет -= Int(запись.размер)
            записи.append(запись)
        }
        var конечноеСостояниеКаталога = stat()
        guard fstat(дескриптор, &конечноеСостояниеКаталога) == 0,
              конечноеСостояниеКаталога.st_dev == исходноеСостояниеКаталога.st_dev,
              конечноеСостояниеКаталога.st_ino == исходноеСостояниеКаталога.st_ino,
              конечноеСостояниеКаталога.st_mtimespec.tv_sec == исходноеСостояниеКаталога.st_mtimespec.tv_sec,
              конечноеСостояниеКаталога.st_mtimespec.tv_nsec == исходноеСостояниеКаталога.st_mtimespec.tv_nsec,
              конечноеСостояниеКаталога.st_mode & 0o777 == исходноеСостояниеКаталога.st_mode & 0o777 else {
            throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
        }
        записи.sort { $0.путь.utf8.lexicographicallyPrecedes($1.путь.utf8) }
        let хэшСнимка = try хэшировать(СодержимоеСнимка(источник: источник, записи: записи.map(КраткоеОписание.init)))
        return СнимокФайловойСистемы(
            источник: источник,
            предшественник: предшественник?.идентификатор,
            записи: записи,
            идентификатор: хэшСнимка,
            физическийКорень: физическийКорень)
    }

    public static func сравнить(
        прежний: СнимокФайловойСистемы,
        новый: СнимокФайловойСистемы
    ) throws -> [ИзменениеФайловойСистемы] {
        guard прежний.источник == новый.источник,
              прежний.физическийКорень == новый.физическийКорень,
              новый.предшественник == прежний.идентификатор else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let до = Dictionary(uniqueKeysWithValues: прежний.записи.map { ($0.путь, $0) })
        let после = Dictionary(uniqueKeysWithValues: новый.записи.map { ($0.путь, $0) })
        let пути = Set(до.keys).union(после.keys).sorted()
        return пути.compactMap { путь in
            switch (до[путь], после[путь]) {
            case (nil, let новое?):
                return ИзменениеФайловойСистемы(вид: .добавлен, путь: путь, прежнийХэш: nil, новыйХэш: новое.хэш)
            case (let прежнее?, nil):
                return ИзменениеФайловойСистемы(вид: .удалён, путь: путь, прежнийХэш: прежнее.хэш, новыйХэш: nil)
            case (let прежнее?, let новое?) where прежнее != новое:
                return ИзменениеФайловойСистемы(вид: .изменён, путь: путь, прежнийХэш: прежнее.хэш, новыйХэш: новое.хэш)
            default:
                return nil
            }
        }
    }

    public static func составитьПлан(
        из снимка: СнимокФайловойСистемы
    ) throws -> ПланПереносаФайловойСистемы {
        guard снимка.записи.count <= пределЗаписей,
              Set(снимка.записи.map(\.путь)).count == снимка.записи.count else {
            throw ОшибкаНаблюденияФайловойСистемы.превышенПредел
        }
        let краткие = снимка.записи.map(КраткоеОписание.init)
        return ПланПереносаФайловойСистемы(
            источник: снимка.источник,
            идентификаторСнимка: снимка.идентификатор,
            записи: снимка.записи,
            хэшПлана: try хэшировать(СодержимоеСнимка(источник: снимка.источник, записи: краткие)),
            кореньИсточника: снимка.физическийКорень)
    }

    public static func перенести(
        по плану: ПланПереносаФайловойСистемы,
        в кореньНазначения: URL
    ) throws -> ИтогПереносаФайловойСистемы {
        let актуальный = try наблюдать(корень: плану.кореньИсточника, источник: плану.источник)
        guard актуальный.идентификатор == плану.идентификаторСнимка,
              try хэшировать(СодержимоеСнимка(
                источник: плану.источник,
                записи: плану.записи.map(КраткоеОписание.init))) == плану.хэшПлана else {
            throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
        }
        let физическийПриёмник = try проверитьВременныйКорень(кореньНазначения)
        let приёмник = try открытьКорень(физическийПриёмник)
        defer { _ = Darwin.close(приёмник) }
        guard try перечислитьИмена(приёмник).isEmpty else {
            throw ОшибкаНаблюденияФайловойСистемы.каталогНеПуст
        }

        for запись in плану.записи {
            do {
                switch запись.тип {
                case .файл:
                    guard let содержимое = запись.содержимое else {
                        throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
                    }
                    try записатьФайл(запись, содержимое: содержимое, в: приёмник)
                case .ссылка:
                    guard let цель = запись.цельСсылки else {
                        throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
                    }
                    try создатьСсылку(имя: запись.путь, цель: цель, в: приёмник)
                }
            } catch let ошибка as ОшибкаНаблюденияФайловойСистемы {
                if ошибка == .несовпадениеСохранения { throw ошибка }
                throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход
            } catch {
                throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход
            }
        }
        guard fsync(приёмник) == 0 else { throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход }

        let снимокНазначения = try наблюдать(корень: физическийПриёмник, источник: плану.источник)
        guard снимокНазначения.идентификатор == плану.идентификаторСнимка,
              снимокНазначения.записи == плану.записи else {
            throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
        }
        return ИтогПереносаФайловойСистемы(
            источник: плану.источник,
            идентификаторСнимкаИсточника: плану.идентификаторСнимка,
            хэшСнимкаПриёмника: снимокНазначения.идентификатор,
            количествоЗаписей: снимокНазначения.записи.count,
            проверкаПовтора: 0,
            физическийИсточник: плану.кореньИсточника,
            физическоеНазначение: физическийПриёмник)
    }

    public static func проверитьСохранение(
        результата: ИтогПереносаФайловойСистемы,
        источник: URL,
        назначение: URL,
        номерПовтора: Int
    ) throws -> ИтогПереносаФайловойСистемы {
        guard номерПовтора > результата.проверкаПовтора else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let физическийИсточник = try проверитьВременныйКорень(источник)
        let физическоеНазначение = try проверитьВременныйКорень(назначение)
        guard физическийИсточник == результата.физическийИсточник,
              физическоеНазначение == результата.физическоеНазначение else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let снятиеИсточника = try наблюдать(корень: физическийИсточник, источник: результата.источник)
        let снятиеНазначения = try наблюдать(корень: физическоеНазначение, источник: результата.источник)
        guard снятиеИсточника.идентификатор == результата.идентификаторСнимкаИсточника,
              снятиеНазначения.идентификатор == результата.хэшСнимкаПриёмника,
              снятиеИсточника.записи == снятиеНазначения.записи,
              снятиеНазначения.записи.count == результата.количествоЗаписей else {
            throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
        }
        return ИтогПереносаФайловойСистемы(
            источник: результата.источник,
            идентификаторСнимкаИсточника: результата.идентификаторСнимкаИсточника,
            хэшСнимкаПриёмника: результата.хэшСнимкаПриёмника,
            количествоЗаписей: результата.количествоЗаписей,
            проверкаПовтора: номерПовтора,
            физическийИсточник: результата.физическийИсточник,
            физическоеНазначение: результата.физическоеНазначение)
    }

    private struct КраткоеОписание: Codable {
        let путь: String
        let тип: ТипЭлементаФайловойСистемы
        let владелец: UInt32
        let режим: UInt16
        let размер: UInt64
        let цельСсылки: String?
        let хэш: String

        init(_ запись: ЗаписьФайловойСистемы) {
            путь = запись.путь; тип = запись.тип; владелец = запись.владелец
            режим = запись.режим; размер = запись.размер
            цельСсылки = запись.цельСсылки; хэш = запись.хэш
        }
    }

    private struct СодержимоеСнимка: Codable {
        let источник: String
        let записи: [КраткоеОписание]
    }

    private static func хэшировать<Значение: Encodable>(_ значение: Значение) throws -> String {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return строкаХэша(Data(SHA256.hash(data: try кодировщик.encode(значение))))
    }

    private static func проверитьВременныйКорень(_ адрес: URL) throws -> URL {
        guard адрес.isFileURL, адрес.path.hasPrefix("/"), !адрес.path.utf8.contains(0) else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let путьКорня = try разрешитьФизическийПуть(адрес.path)
        let путьВременного = try разрешитьФизическийПуть(FileManager.default.temporaryDirectory.path)
        let префикс = путьВременного.hasSuffix("/") ? путьВременного : путьВременного + "/"
        guard путьКорня.hasPrefix(префикс) else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        return URL(fileURLWithPath: путьКорня, isDirectory: true)
    }

    private static func разрешитьФизическийПуть(_ путь: String) throws -> String {
        guard let физический = realpath(путь, nil) else {
            throw ОшибкаНаблюденияФайловойСистемы.система(errno)
        }
        defer { free(физический) }
        return String(cString: физический)
    }

    private static func перечислитьИмена(_ корень: Int32) throws -> [String] {
        let копия = dup(корень)
        guard копия >= 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
        guard let поток = fdopendir(копия) else {
            _ = Darwin.close(копия)
            throw ОшибкаНаблюденияФайловойСистемы.система(errno)
        }
        defer { closedir(поток) }
        var имена: [String] = []
        while true {
            errno = 0
            guard let запись = readdir(поток) else {
                if errno != 0 { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
                break
            }
            let указатель = withUnsafePointer(to: &запись.pointee.d_name) {
                $0.withMemoryRebound(to: CChar.self, capacity: Int(NAME_MAX) + 1) { $0 }
            }
            guard let имя = String(validatingCString: указатель), !имя.isEmpty else {
                throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("имя-не-utf8")
            }
            if имя == "." || имя == ".." { continue }
            guard !имя.contains("/"), !имя.utf8.contains(0) else {
                throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("небезопасное-имя")
            }
            имена.append(имя)
            guard имена.count <= пределЗаписей else { throw ОшибкаНаблюденияФайловойСистемы.превышенПредел }
        }
        return имена
    }

    private static func снять(
        дескрипторКорня корень: Int32,
        имя: String,
        пределБайтов: Int
    ) throws -> ЗаписьФайловойСистемы {
        var исходныеСведения = stat()
        let найден = имя.withCString { fstatat(корень, $0, &исходныеСведения, AT_SYMLINK_NOFOLLOW) }
        guard найден == 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
        let владелец = UInt32(исходныеСведения.st_uid)
        guard владелец == UInt32(geteuid()), исходныеСведения.st_mode & 0o022 == 0 else {
            throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("владелец-или-права")
        }
        let режим = UInt16(исходныеСведения.st_mode & 0o777)
        switch исходныеСведения.st_mode & S_IFMT {
        case S_IFREG:
            let размер = Int(исходныеСведения.st_size)
            guard исходныеСведения.st_nlink == 1, размер >= 0,
                  размер <= пределФайла, размер <= пределБайтов else {
                throw ОшибкаНаблюденияФайловойСистемы.превышенПредел
            }
            let дескриптор = имя.withCString {
                openat(корень, $0, O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC)
            }
            guard дескриптор >= 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
            defer { _ = Darwin.close(дескриптор) }
            var доЧтения = stat()
            guard fstat(дескриптор, &доЧтения) == 0, доЧтения.st_dev == исходныеСведения.st_dev,
                  доЧтения.st_ino == исходныеСведения.st_ino,
                  доЧтения.st_mode & S_IFMT == S_IFREG else {
                throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
            }
            let содержимое = try прочитать(дескриптор, 0, размер)
            var послеЧтения = stat()
            guard fstat(дескриптор, &послеЧтения) == 0,
                  послеЧтения.st_dev == доЧтения.st_dev,
                  послеЧтения.st_ino == доЧтения.st_ino,
                  послеЧтения.st_uid == доЧтения.st_uid,
                  послеЧтения.st_nlink == доЧтения.st_nlink,
                  послеЧтения.st_size == доЧтения.st_size,
                  послеЧтения.st_mtimespec.tv_sec == доЧтения.st_mtimespec.tv_sec,
                  послеЧтения.st_mtimespec.tv_nsec == доЧтения.st_mtimespec.tv_nsec,
                  послеЧтения.st_mode & 0o777 == доЧтения.st_mode & 0o777 else {
                throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
            }
            return ЗаписьФайловойСистемы(
                путь: имя, тип: .файл, владелец: владелец, режим: режим,
                размер: UInt64(размер), содержимое: содержимое, цельСсылки: nil,
                хэш: строкаХэша(Data(SHA256.hash(data: содержимое))))
        case S_IFLNK:
            let цель = try прочитатьЦельСсылки(корень: корень, имя: имя)
            var конечныеСведения = stat()
            let повторнаяПроверка = имя.withCString {
                fstatat(корень, $0, &конечныеСведения, AT_SYMLINK_NOFOLLOW)
            }
            guard повторнаяПроверка == 0, конечныеСведения.st_dev == исходныеСведения.st_dev,
                  конечныеСведения.st_ino == исходныеСведения.st_ino,
                  конечныеСведения.st_mode & S_IFMT == S_IFLNK else {
                throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
            }
            let части = цель.split(separator: "/", omittingEmptySubsequences: false)
            guard !цель.hasPrefix("/"), !части.contains(".."), !цель.isEmpty else {
                throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("ссылка-вне-каталога")
            }
            let байты = Data(цель.utf8)
            return ЗаписьФайловойСистемы(
                путь: имя, тип: .ссылка, владелец: владелец, режим: режим,
                размер: UInt64(байты.count), содержимое: nil, цельСсылки: цель,
                хэш: строкаХэша(Data(SHA256.hash(data: байты))))
        default:
            throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("тип-файловой-системы")
        }
    }

    private static func прочитатьЦельСсылки(корень: Int32, имя: String) throws -> String {
        var буфер = [CChar](repeating: 0, count: пределСсылки)
        let число = имя.withCString { путь in
            буфер.withUnsafeMutableBufferPointer { readlinkat(корень, путь, $0.baseAddress!, $0.count) }
        }
        guard число >= 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
        guard число < пределСсылки,
              let цель = String(bytes: буфер.prefix(число).map { UInt8(bitPattern: $0) }, encoding: .utf8) else {
            throw ОшибкаНаблюденияФайловойСистемы.превышенПредел
        }
        return цель
    }

    private static func записатьФайл(
        _ запись: ЗаписьФайловойСистемы,
        содержимое: Data,
        в корень: Int32
    ) throws {
        guard !запись.путь.contains("/"), запись.владелец == UInt32(geteuid()),
              запись.размер == содержимое.count,
              строкаХэша(Data(SHA256.hash(data: содержимое))) == запись.хэш else {
            throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
        }
        let дескриптор = запись.путь.withCString {
            openat(корень, $0, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        }
        guard дескриптор >= 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
        defer { _ = Darwin.close(дескриптор) }
        var смещение = 0
        do {
            try содержимое.withUnsafeBytes { буфер in
                while смещение < буфер.count {
                    let число = Darwin.write(дескриптор, буфер.baseAddress!.advanced(by: смещение), буфер.count - смещение)
                    if число < 0 && errno == EINTR { continue }
                    guard число > 0 else { throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход }
                    смещение += число
                }
            }
            guard fchmod(дескриптор, mode_t(запись.режим)) == 0, fsync(дескриптор) == 0 else {
                throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход
            }
        } catch {
            throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход
        }
    }

    private static func создатьСсылку(имя: String, цель: String, в корень: Int32) throws {
        guard !имя.contains("/"), !цель.hasPrefix("/"), !цель.split(separator: "/").contains("..") else {
            throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
        }
        let результат = цель.withCString { target in имя.withCString { symlinkat(target, корень, $0) } }
        guard результат == 0 else { throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход }
    }

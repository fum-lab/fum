public enum НаблюдениеФайловойСистемы {
    private static let пределФайла = Пределы.фрагмент
    private static let пределЗаписей = 64
    private static let пределСсылки = 4096
    private static let пределСнимка = Int(Пределы.объект)
    private static let попыткиПереноса = РеестрПопытокПереносаФайловойСистемы()

    public static func наблюдать(
        корень: URL,
        источник: String,
        предшественник: СнимокФайловойСистемы? = nil
    ) throws -> СнимокФайловойСистемы {
        try наблюдать(
            корень: корень,
            источник: источник,
            предшественник: предшественник,
            через: НативныйПоставщикСистемныхВызововФайловойСистемы())
    }

    static func наблюдать(
        корень: URL,
        источник: String,
        предшественник: СнимокФайловойСистемы? = nil,
        через поставщик: any ПоставщикСистемныхВызововФайловойСистемы
    ) throws -> СнимокФайловойСистемы {
        guard !источник.isEmpty, источник.utf8.count <= 256,
              предшественник == nil || предшественник?.источник == источник else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let физическийКорень = try проверитьВременныйКорень(корень)
        let дескриптор = try открытьКорень(физическийКорень)
        defer { _ = Darwin.close(дескриптор) }

        var исходноеСостояниеКаталога = stat()
        guard поставщик.fstat(дескриптор, &исходноеСостояниеКаталога) == 0,
              исходноеСостояниеКаталога.st_mode & S_IFMT == S_IFDIR else {
            throw ОшибкаНаблюденияФайловойСистемы.система(errno)
        }
        let имена = try перечислитьИмена(дескриптор)
        guard имена.count <= пределЗаписей else { throw ОшибкаНаблюденияФайловойСистемы.превышенПредел }
        guard Set(имена).count == имена.count else {
            throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("нормализующая-коллизия-имён")
        }
        var записи: [ЗаписьФайловойСистемы] = []
        записи.reserveCapacity(имена.count)
        var оставшийсяБюджет = пределСнимка
        for имя in имена {
            let запись = try снять(
                дескрипторКорня: дескриптор, имя: имя,
                пределБайтов: оставшийсяБюджет, через: поставщик)
            guard запись.размер <= UInt64(оставшийсяБюджет) else {
                throw ОшибкаНаблюденияФайловойСистемы.превышенПредел
            }
            оставшийсяБюджет -= Int(запись.размер)
            записи.append(запись)
        }
        var конечноеСостояниеКаталога = stat()
        // Граничные сведения каталога не доказывают общий атомарный снимок его содержимого.
        guard поставщик.fstat(дескриптор, &конечноеСостояниеКаталога) == 0,
              одинаковыеСведения(
                конечноеСостояниеКаталога, исходноеСостояниеКаталога,
                сравниваяВремяДоступа: false) else {
            throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
        }
        записи.sort { $0.путь.utf8.lexicographicallyPrecedes($1.путь.utf8) }
        let хэшСнимка = try хэшировать(СодержимоеСнимка(источник: источник, записи: записи.map(КраткоеОписание.init)))
        return СнимокФайловойСистемы(
            источник: источник,
            предшественник: предшественник?.идентификатор,
            записи: записи,
            идентификатор: хэшСнимка,
            границаСогласованности: .объектыПровереныПоОтдельностиОбщаяАтомарностьНеДоказана,
            физическийКорень: физическийКорень)
    }

    public static func сравнить(
        прежний: СнимокФайловойСистемы,
        новый: СнимокФайловойСистемы
    ) throws -> [ИзменениеФайловойСистемы] {
        guard прежний.источник == новый.источник,
              прежний.физическийКорень == новый.физическийКорень,
              новый.предшественник == прежний.идентификатор else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let до = Dictionary(uniqueKeysWithValues: прежний.записи.map { ($0.путь, $0) })
        let после = Dictionary(uniqueKeysWithValues: новый.записи.map { ($0.путь, $0) })
        let пути = Set(до.keys).union(после.keys).sorted()
        return пути.compactMap { путь in
            switch (до[путь], после[путь]) {
            case (nil, let новое?):
                return ИзменениеФайловойСистемы(вид: .добавлен, путь: путь, прежнийХэш: nil, новыйХэш: новое.хэш)
            case (let прежнее?, nil):
                return ИзменениеФайловойСистемы(вид: .удалён, путь: путь, прежнийХэш: прежнее.хэш, новыйХэш: nil)
            case (let прежнее?, let новое?) where прежнее != новое:
                return ИзменениеФайловойСистемы(вид: .изменён, путь: путь, прежнийХэш: прежнее.хэш, новыйХэш: новое.хэш)
            default:
                return nil
            }
        }
    }

    public static func составитьПлан(
        из снимка: СнимокФайловойСистемы
    ) throws -> ПланПереносаФайловойСистемы {
        guard снимка.записи.count <= пределЗаписей,
              Set(снимка.записи.map(\.путь)).count == снимка.записи.count else {
            throw ОшибкаНаблюденияФайловойСистемы.превышенПредел
        }
        let краткие = снимка.записи.map(КраткоеОписание.init)
        return ПланПереносаФайловойСистемы(
            источник: снимка.источник,
            идентификаторСнимка: снимка.идентификатор,
            записи: снимка.записи,
            хэшПлана: try хэшировать(СодержимоеСнимка(источник: снимка.источник, записи: краткие)),
            кореньИсточника: снимка.физическийКорень)
    }

    public static func перенести(
        по плану: ПланПереносаФайловойСистемы,
        в кореньНазначения: URL
    ) throws -> ИтогПереносаФайловойСистемы {
        try перенести(
            по: плану,
            в: кореньНазначения,
            прочитатьНазначение: { корень, источник in
                try наблюдать(корень: корень, источник: источник)

private final class РеестрПопытокПереносаФайловойСистемы: @unchecked Sendable {
    // Запрещает повтор той же операции в текущем процессе; свидетельство переносится вызывающему коду.
    private let блокировка = NSLock()
    private var ключи: Set<КлючПопыткиПереносаФайловойСистемы> = []

    func ужеНачата(_ ключ: КлючПопыткиПереносаФайловойСистемы) -> Bool {
        блокировка.lock()
        defer { блокировка.unlock() }
        return ключи.contains(ключ)
    }

    func зарегистрировать(_ ключ: КлючПопыткиПереносаФайловойСистемы) -> Bool {
        блокировка.lock()
        defer { блокировка.unlock() }
        return ключи.insert(ключ).inserted
    }
}

private struct НативныйПоставщикСистемныхВызововФайловойСистемы: ПоставщикСистемныхВызововФайловойСистемы {
    func fstat(_ дескриптор: Int32, _ сведения: UnsafeMutablePointer<stat>) -> Int32 {
        Darwin.fstat(дескриптор, сведения)
    }

    func fstatat(_ каталог: Int32, _ имя: String, _ сведения: UnsafeMutablePointer<stat>, _ флаги: Int32) -> Int32 {
        имя.withCString { Darwin.fstatat(каталог, $0, сведения, флаги) }
    }

    func openat(_ каталог: Int32, _ имя: String, _ флаги: Int32) -> Int32 {
        имя.withCString { Darwin.openat(каталог, $0, флаги) }
    }
}


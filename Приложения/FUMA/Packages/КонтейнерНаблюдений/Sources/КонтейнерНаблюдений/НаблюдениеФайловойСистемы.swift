    private static func хэшировать<Значение: Encodable>(_ значение: Значение) throws -> String {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return строкаХэша(Data(SHA256.hash(data: try кодировщик.encode(значение))))
    }

    private static func проверитьВременныйКорень(_ адрес: URL) throws -> URL {
        guard адрес.isFileURL, адрес.path.hasPrefix("/"), !адрес.path.utf8.contains(0) else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        let путьКорня = try разрешитьФизическийПуть(адрес.path)
        let путьВременного = try разрешитьФизическийПуть(FileManager.default.temporaryDirectory.path)
        let префикс = путьВременного.hasSuffix("/") ? путьВременного : путьВременного + "/"
        guard путьКорня.hasPrefix(префикс) else {
            throw ОшибкаНаблюденияФайловойСистемы.недопустимыйИсточник
        }
        return URL(fileURLWithPath: путьКорня, isDirectory: true)
    }

    private static func разрешитьФизическийПуть(_ путь: String) throws -> String {
        guard let физический = realpath(путь, nil) else {
            throw ОшибкаНаблюденияФайловойСистемы.система(errno)
        }
        defer { free(физический) }
        return String(cString: физический)
    }

    private static func перечислитьИмена(_ корень: Int32) throws -> [String] {
        let копия = dup(корень)
        guard копия >= 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
        guard let поток = fdopendir(копия) else {
            _ = Darwin.close(копия)
            throw ОшибкаНаблюденияФайловойСистемы.система(errno)
        }
        defer { closedir(поток) }
        var имена: [String] = []
        while true {
            errno = 0
            guard let запись = readdir(поток) else {
                if errno != 0 { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
                break
            }
            let указатель = withUnsafePointer(to: &запись.pointee.d_name) {
                $0.withMemoryRebound(to: CChar.self, capacity: Int(NAME_MAX) + 1) { $0 }
            }
            guard let имя = String(validatingCString: указатель), !имя.isEmpty else {
                throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("имя-не-utf8")
            }
            if имя == "." || имя == ".." { continue }
            guard !имя.contains("/"), !имя.utf8.contains(0) else {
                throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("небезопасное-имя")
            }
            имена.append(имя)
            guard имена.count <= пределЗаписей else { throw ОшибкаНаблюденияФайловойСистемы.превышенПредел }
        }
        return имена
    }

    private static func снять(
        дескрипторКорня корень: Int32,
        имя: String,
        пределБайтов: Int,
        через поставщик: any ПоставщикСистемныхВызововФайловойСистемы
    ) throws -> ЗаписьФайловойСистемы {
        var исходныеСведения = stat()
        let найден = поставщик.fstatat(корень, имя, &исходныеСведения, AT_SYMLINK_NOFOLLOW)
        guard найден == 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
        let владелец = UInt32(исходныеСведения.st_uid)
        guard владелец == UInt32(geteuid()), исходныеСведения.st_mode & 0o022 == 0 else {
            throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("владелец-или-права")
        }
        let режим = UInt16(исходныеСведения.st_mode & 0o777)
        switch исходныеСведения.st_mode & S_IFMT {
        case S_IFREG:
            let размер = Int(исходныеСведения.st_size)
            guard исходныеСведения.st_nlink == 1, размер >= 0,
                  размер <= пределФайла, размер <= пределБайтов else {
                throw ОшибкаНаблюденияФайловойСистемы.превышенПредел
            }
            let дескриптор = поставщик.openat(корень, имя, O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC)
            guard дескриптор >= 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
            defer { _ = Darwin.close(дескриптор) }
            var доЧтения = stat()
            guard поставщик.fstat(дескриптор, &доЧтения) == 0,
                  одинаковыеСведения(доЧтения, исходныеСведения),
                  доЧтения.st_mode & S_IFMT == S_IFREG else {
                throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
            }
            let содержимое = try прочитать(дескриптор, 0, размер)
            var послеЧтения = stat()
            guard поставщик.fstat(дескриптор, &послеЧтения) == 0,
                  одинаковыеСведения(послеЧтения, доЧтения, сравниваяВремяДоступа: false),
                  содержимое.count == размер,
                  послеЧтения.st_size == Int64(размер) else {
                throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
            }
            return ЗаписьФайловойСистемы(
                путь: имя, тип: .файл, владелец: владелец, режим: режим,
                размер: UInt64(размер), содержимое: содержимое, цельСсылки: nil,
                хэш: строкаХэша(Data(SHA256.hash(data: содержимое))))
        case S_IFLNK:
            let цель = try прочитатьЦельСсылки(корень: корень, имя: имя)
            var конечныеСведения = stat()
            let повторнаяПроверка = поставщик.fstatat(
                корень, имя, &конечныеСведения, AT_SYMLINK_NOFOLLOW)
            guard повторнаяПроверка == 0,
                  одинаковыеСведения(конечныеСведения, исходныеСведения),
                  конечныеСведения.st_mode & S_IFMT == S_IFLNK else {
                throw ОшибкаНаблюденияФайловойСистемы.источникИзменился
            }
            let части = цель.split(separator: "/", omittingEmptySubsequences: false)
            guard !цель.hasPrefix("/"), !части.contains(".."), !цель.isEmpty else {
                throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("ссылка-вне-каталога")
            }
            let байты = Data(цель.utf8)
            return ЗаписьФайловойСистемы(
                путь: имя, тип: .ссылка, владелец: владелец, режим: режим,
                размер: UInt64(байты.count), содержимое: nil, цельСсылки: цель,
                хэш: строкаХэша(Data(SHA256.hash(data: байты))))
        default:
            throw ОшибкаНаблюденияФайловойСистемы.неподдержанныйОбъект("тип-файловой-системы")
        }
    }

    private static func одинаковыеСведения(
        _ левые: stat,
        _ правые: stat,
        сравниваяВремяДоступа: Bool = true
    ) -> Bool {
        let одинаковоеВремяДоступа = !сравниваяВремяДоступа
            || (левые.st_atimespec.tv_sec == правые.st_atimespec.tv_sec
                && левые.st_atimespec.tv_nsec == правые.st_atimespec.tv_nsec)
        return одинаковоеВремяДоступа
            && левые.st_dev == правые.st_dev
            && левые.st_ino == правые.st_ino
            && левые.st_mode == правые.st_mode
            && левые.st_nlink == правые.st_nlink
            && левые.st_uid == правые.st_uid
            && левые.st_gid == правые.st_gid
            && левые.st_rdev == правые.st_rdev
            && левые.st_size == правые.st_size
            && левые.st_blocks == правые.st_blocks
            && левые.st_blksize == правые.st_blksize
            && левые.st_flags == правые.st_flags
            && левые.st_gen == правые.st_gen
            && левые.st_mtimespec.tv_sec == правые.st_mtimespec.tv_sec
            && левые.st_mtimespec.tv_nsec == правые.st_mtimespec.tv_nsec
            && левые.st_ctimespec.tv_sec == правые.st_ctimespec.tv_sec
            && левые.st_ctimespec.tv_nsec == правые.st_ctimespec.tv_nsec
            && левые.st_birthtimespec.tv_sec == правые.st_birthtimespec.tv_sec
            && левые.st_birthtimespec.tv_nsec == правые.st_birthtimespec.tv_nsec
    }

    private static func прочитатьЦельСсылки(корень: Int32, имя: String) throws -> String {
        var буфер = [CChar](repeating: 0, count: пределСсылки)
        let число = имя.withCString { путь in
            буфер.withUnsafeMutableBufferPointer { readlinkat(корень, путь, $0.baseAddress!, $0.count) }
        }
        guard число >= 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
        guard число < пределСсылки,
              let цель = String(bytes: буфер.prefix(число).map { UInt8(bitPattern: $0) }, encoding: .utf8) else {
            throw ОшибкаНаблюденияФайловойСистемы.превышенПредел
        }
        return цель
    }

    private static func записатьФайл(
        _ запись: ЗаписьФайловойСистемы,
        содержимое: Data,
        в корень: Int32
    ) throws {
        guard !запись.путь.contains("/"), запись.владелец == UInt32(geteuid()),
              запись.размер == содержимое.count,
              строкаХэша(Data(SHA256.hash(data: содержимое))) == запись.хэш else {
            throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
        }
        let дескриптор = запись.путь.withCString {
            openat(корень, $0, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        }
        guard дескриптор >= 0 else { throw ОшибкаНаблюденияФайловойСистемы.система(errno) }
        defer { _ = Darwin.close(дескриптор) }
        var смещение = 0
        do {
            try содержимое.withUnsafeBytes { буфер in
                while смещение < буфер.count {
                    let число = Darwin.write(дескриптор, буфер.baseAddress!.advanced(by: смещение), буфер.count - смещение)
                    if число < 0 && errno == EINTR { continue }
                    guard число > 0 else { throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход }
                    смещение += число
                }
            }
            guard fchmod(дескриптор, mode_t(запись.режим)) == 0, fsync(дескриптор) == 0 else {
                throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход
            }
        } catch {
            throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход
        }
    }

    private static func создатьСсылку(имя: String, цель: String, в корень: Int32) throws {
        guard !имя.contains("/"), !цель.hasPrefix("/"), !цель.split(separator: "/").contains("..") else {
            throw ОшибкаНаблюденияФайловойСистемы.несовпадениеСохранения
        }
        let результат = цель.withCString { target in имя.withCString { symlinkat(target, корень, $0) } }
        guard результат == 0 else { throw ОшибкаНаблюденияФайловойСистемы.неизвестныйИсход }
    }

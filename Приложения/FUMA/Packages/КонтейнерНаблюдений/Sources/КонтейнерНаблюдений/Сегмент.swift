import Foundation
import Darwin
import CryptoKit

/// Необязательное наблюдение одного синхронного владельца; содержимое записей не сохраняет.
public final class НаблюдениеПоискаСегмента {
    public private(set) var построеноИндекса = 0
    public private(set) var посещеноПриПоиске = 0
    public private(set) var скопированоКвитанций = 0
    public private(set) var адресныхОбращений = 0
    public private(set) var прочитаноГруппСнимка = 0
    public private(set) var хэшированоБайтовДанных = 0
    public init() {}
    fileprivate func построенЭлемент() { if построеноИндекса < Int.max { построеноИндекса += 1 } }
    fileprivate func посещёнЭлемент() { if посещеноПриПоиске < Int.max { посещеноПриПоиске += 1 } }
    fileprivate func скопированаКвитанция() { if скопированоКвитанций < Int.max { скопированоКвитанций += 1 } }
    fileprivate func адресноеОбращение() { if адресныхОбращений < Int.max { адресныхОбращений += 1 } }
    fileprivate func прочитанаГруппаСнимка() {
        if прочитаноГруппСнимка < Int.max { прочитаноГруппСнимка += 1 }
    }
    fileprivate func хэшированыДанные(_ байты: Int) {
        let (сумма, переполнение) = хэшированоБайтовДанных.addingReportingOverflow(байты)
        хэшированоБайтовДанных = переполнение ? Int.max : сумма
    }
}

/// Один синхронный владелец. Не Sendable: вызовы одного экземпляра не перекрываются.
/// Межпроцессный advisory flock удерживается до закрытия этого экземпляра.
public final class Сегмент {
    private var дескриптор: Int32 = -1
    private var каталог: Int32 = -1
    private let запись: Bool
    private let операции: ФайловыеОперации
    private let наблюдениеПоиска: НаблюдениеПоискаСегмента?
    private var снимок = Снимок()
    private var индексГрупп: [String: Int] = [:]
    private var отказ = false
    public private(set) var профиль: [МеткаПрофиля] = []
    private let профилировать: Bool
    private var глубина = 0

    public var записи: [Квитанция] {
        снимок.группы.map { группа in
            наблюдениеПоиска?.скопированаКвитанция()
            return группа.квитанция
        }
    }
    public var естьХвост: Bool { снимок.хвост }
    var подтверждённыхФрагментов: Int { снимок.подтверждённыхФрагментов }

    public init(кореньДанных: URL, запись: Bool, создать: Bool = true,
                операции: ФайловыеОперации = .системные,
                профилировать: Bool = false,
                наблюдениеПоиска: НаблюдениеПоискаСегмента? = nil) throws {
        self.запись = запись
        self.операции = операции
        self.профилировать = профилировать
        self.наблюдениеПоиска = наблюдениеПоиска
        каталог = try открытьКорень(кореньДанных)
        do {
            // Общий замок существующего корня берётся до появления пустого файла.
            // Иначе конкурент мог бы захватить новый файл между O_EXCL и flock.
            try повторПриСигнале {
                guard flock(каталог, (запись ? LOCK_EX : LOCK_SH) | LOCK_NB) == 0 else {
                    if errno == EWOULDBLOCK { throw ОшибкаКонтейнера.занят }
                    throw ОшибкаКонтейнера.система(errno)
                }
            }
            let флаги = (запись ? O_RDWR : O_RDONLY) | O_CLOEXEC | O_NOFOLLOW | O_NONBLOCK
            var создан = false
            if запись && создать {
                дескриптор = openat(каталог, "сегмент.fumobs", флаги | O_CREAT | O_EXCL, 0o600)
                if дескриптор >= 0 { создан = true }
                else if errno != EEXIST { throw ОшибкаКонтейнера.система(errno) }
            }
            if !создан { дескриптор = openat(каталог, "сегмент.fumobs", флаги) }
            guard дескриптор >= 0 else { throw ОшибкаКонтейнера.система(errno) }
            _ = try размерФайла(дескриптор)
            try повторПриСигнале {
                guard flock(дескриптор, (запись ? LOCK_EX : LOCK_SH) | LOCK_NB) == 0 else {
                    if errno == EWOULDBLOCK { throw ОшибкаКонтейнера.занят }
                    throw ОшибкаКонтейнера.система(errno)
                }
            }
            if создан {
                try записатьПолностью(сигнатура)
                try синхронизировать()
            }
            let проверенный = try измерить("сканирование") { try сканировать(дескриптор) }
            let индекс = try построитьИндекс(проверенный)
            снимок = проверенный
            подключитьНаблюдениеГрупп()
            индексГрупп = индекс
        } catch {
            закрыть()
            throw error
        }
    }

    deinit { закрыть() }

    public func закрыть() {
        // Явный unlock завершает владение даже при временно унаследованном fork fd.
        // Один экземпляр не используют через fork. close после EINTR не повторяется.
        func освободить(_ fd: Int32) {
            guard fd >= 0 else { return }
            while flock(fd, LOCK_UN) != 0 && errno == EINTR {}
            _ = Darwin.close(fd)
        }
        освободить(дескриптор); дескриптор = -1
        освободить(каталог); каталог = -1
    }

    public func очиститьПрофиль() { профиль.removeAll(keepingCapacity: true) }

    private func измерить<Значение>(_ этап: String, _ действие: () throws -> Значение) rethrows -> Значение {
        guard профилировать else { return try действие() }
        let начало = DispatchTime.now().uptimeNanoseconds
        let уровень = глубина
        глубина += 1
        var исход = "неуспешно"
        defer {
            глубина -= 1
            // Диагностика тоже ограничена и никогда не меняет исход файловой операции.
            if профиль.count < 4096 {
                профиль.append(МеткаПрофиля(этап: этап,
                    наносекунды: DispatchTime.now().uptimeNanoseconds - начало,
                    исход: исход, глубина: уровень))
            }
        }
        let результат = try действие()
        исход = "успешно"
        return результат
    }

    private func проверитьДоступ(_ дляЗаписи: Bool = false) throws {
        guard дескриптор >= 0, !отказ else { throw ОшибкаКонтейнера.закрыт }
        if дляЗаписи, !запись { throw ОшибкаКонтейнера.толькоЧтение }
    }

    private func построитьИндекс(_ проверенный: Снимок) throws -> [String: Int] {
        var индекс: [String: Int] = [:]
        индекс.reserveCapacity(проверенный.группы.count)
        for (позиция, группа) in проверенный.группы.enumerated() {
            наблюдениеПоиска?.построенЭлемент()
            guard индекс.updateValue(позиция, forKey: группа.квитанция.описание.идентификатор) == nil else {
                throw ОшибкаКонтейнера.повреждение
            }
        }
        return индекс
    }

    private func подключитьНаблюдениеГрупп() {
        if let наблюдениеПоиска {
            снимок.группы.приЧтении = { наблюдениеПоиска.прочитанаГруппаСнимка() }
        }
    }

    private func найтиГруппу(_ идентификатор: String) -> Группа? {
        наблюдениеПоиска?.адресноеОбращение()
        guard let позиция = индексГрупп[идентификатор] else { return nil }
        наблюдениеПоиска?.посещёнЭлемент()
        return снимок.группы[позиция]
    }

    private func записатьПолностью(_ данные: Data) throws {
        try данные.withUnsafeBytes { (буфер: UnsafeRawBufferPointer) in
            var смещение = 0
            while смещение < буфер.count {
                let остаток = UnsafeRawBufferPointer(rebasing: буфер[смещение...])
                let число = try повторПриСигнале { try операции.запись(дескриптор, остаток) }
                guard число > 0, число <= остаток.count else { throw ОшибкаКонтейнера.система(EIO) }
                смещение += число
            }
        }
    }

    private func синхронизировать() throws {
        try измерить("синхронизация-файла") {
            try повторПриСигнале { try операции.синхронизация(дескриптор) }
        }
        try измерить("синхронизация-каталога") {
            try повторПриСигнале { try операции.синхронизация(каталог) }
        }
    }

    public func добавить(_ описание: ОписаниеНаблюдения, данные: Data) throws -> Квитанция {
        try проверитьДоступ(true)
        return try измерить("подтверждение") {
            try проверитьОписание(описание)
            guard данные.count <= Пределы.объект else { throw ОшибкаКонтейнера.предел }
            guard !снимок.хвост else { throw ОшибкаКонтейнера.неполныйХвост }
            let хэшДанных = измерить("хэш-входа") {
                наблюдениеПоиска?.хэшированыДанные(данные.count)
                return строкаХэша(хэш(данные))
            }
            if let группа = найтиГруппу(описание.идентификатор) {
                guard группа.квитанция.описание == описание,
                      группа.квитанция.размер == данные.count,
                      группа.квитанция.хэш == хэшДанных else { throw ОшибкаКонтейнера.конфликтИдентификатора }
                // Восстановленный commit может быть видимым после неуспешного fsync.
                // Даже повтор в новом процессе обязан заново успешно синхронизировать.
                do { try синхронизировать() }
                catch { отказ = true; throw error }
                return группа.квитанция
            }
            guard снимок.группы.count < Пределы.записи else { throw ОшибкаКонтейнера.предел }
            let количество = (данные.count + Пределы.фрагмент - 1) / Пределы.фрагмент
            guard количество <= Пределы.фрагменты - снимок.подтверждённыхФрагментов else {
                throw ОшибкаКонтейнера.предел
            }
            let начало = try кодировать(описание)
            let конец = try кодировать(Фиксация(размер: UInt64(данные.count), фрагменты: количество, хэш: хэшДанных))
            var заголовки: [Data] = []
            var длина = 88 + начало.count + 88 + конец.count
            for номер in 0..<количество {
                let заголовок = try кодировать(Фрагмент(номер: номер, смещение: UInt64(номер * Пределы.фрагмент)))
                заголовки.append(заголовок)
                длина += 88 + заголовок.count + min(Пределы.фрагмент, данные.count - номер * Пределы.фрагмент)
            }
            guard длина <= Пределы.сегмент - снимок.конец else { throw ОшибкаКонтейнера.предел }
            do {
                guard lseek(дескриптор, off_t(снимок.конец), SEEK_SET) >= 0 else {
                    throw ОшибкаКонтейнера.система(errno)
                }
                var номер = снимок.следующийНомер
                var предыдущий = снимок.предыдущийХэш
                var позиция = снимок.конец
                var участки: [Участок] = []
                func кадр(_ вид: UInt8, _ заголовок: Data, _ байты: Data) throws {
                    var префикс = Data("OBS1".utf8)
                    префикс.append(contentsOf: [вид, 0, 0, 0])
                    префикс.append(байтыЧисла(UInt64(заголовок.count), 4))
                    префикс.append(байтыЧисла(UInt64(байты.count), 4))
                    префикс.append(байтыЧисла(номер, 8))
                    var счётчик = SHA256()
                    счётчик.update(data: предыдущий); счётчик.update(data: префикс)
                    наблюдениеПоиска?.хэшированыДанные(байты.count)
                    счётчик.update(data: заголовок); счётчик.update(data: байты)
                    let следующий = Data(счётчик.finalize())
                    try записатьПолностью(префикс)
                    try записатьПолностью(хэш(префикс))
                    try записатьПолностью(заголовок)
                    try записатьПолностью(байты)
                    try записатьПолностью(следующий)
                    if вид == 2 {
                        наблюдениеПоиска?.хэшированыДанные(байты.count)
                        участки.append(Участок(начало: позиция + 56 + заголовок.count,
                                              длина: байты.count, хэш: хэш(байты)))
                    }
                    позиция += 88 + заголовок.count + байты.count
                    номер += 1; предыдущий = следующий
                }
                try измерить("запись-группы") {
                    try кадр(1, начало, Data())
                    for номер in 0..<количество {
                        let смещение = номер * Пределы.фрагмент
                        let началоСреза = данные.startIndex + смещение
                        let конецСреза = данные.startIndex + min(смещение + Пределы.фрагмент, данные.count)
                        try кадр(2, заголовки[номер], данные.subdata(in: началоСреза..<конецСреза))
                    }
                    try кадр(3, конец, Data())
                }
                try синхронизировать()
                let квитанция = Квитанция(описание: описание, размер: UInt64(данные.count), хэш: хэшДанных)
                let позицияГруппы = снимок.группы.count
                снимок.группы.append(Группа(квитанция: квитанция, участки: участки))
                снимок.подтверждённыхФрагментов += количество
                индексГрупп[описание.идентификатор] = позицияГруппы
                снимок.конец = позиция; снимок.следующийНомер = номер; снимок.предыдущийХэш = предыдущий
                return квитанция
            } catch {
                отказ = true
                throw error
            }
        }
    }

    public func квитанция(_ идентификатор: String) throws -> Квитанция {
        try проверитьДоступ()
        guard let группа = найтиГруппу(идентификатор) else { throw ОшибкаКонтейнера.нетЗаписи }
        return группа.квитанция
    }

    public func извлечь(_ идентификатор: String) throws -> Data {
        try проверитьДоступ()
        guard let группа = найтиГруппу(идентификатор) else {
            throw ОшибкаКонтейнера.нетЗаписи
        }
        do {
            var данные = Data()
            данные.reserveCapacity(Int(группа.квитанция.размер))
            for участок in группа.участки {
                let фрагмент = try прочитать(дескриптор, участок.начало, участок.длина)
                guard хэш(фрагмент) == участок.хэш else { throw ОшибкаКонтейнера.повреждение }
                данные.append(фрагмент)
            }
            return данные
        } catch { отказ = true; throw error }
    }

    public func восстановитьХвост() throws {
        try проверитьДоступ(true)
        try измерить("восстановление") {
            do {
                // Повторная проверка всего committed prefix до любой деструктивной операции.
                let проверенный = try сканировать(дескриптор)
                let индекс = try построитьИндекс(проверенный)
                if проверенный.хвост {
                    try повторПриСигнале {
                        guard ftruncate(дескриптор, off_t(проверенный.конец)) == 0 else {
                            throw ОшибкаКонтейнера.система(errno)
                        }
                    }
                }
                try синхронизировать()
                снимок = проверенный; подключитьНаблюдениеГрупп()
                индексГрупп = индекс; снимок.хвост = false
            } catch { отказ = true; throw error }
        }
    }
}

        return try JSONDecoder().decode(
            ФикстураКлавиатурыИРамки.self,
            from: Data(contentsOf: путьФикстуры)
        )
    }

    private func наблюдениеРамки(
        _ событие: СобытиеРамкиФикстуры,
        из фикстуры: ФикстураКлавиатурыИРамки
    ) throws -> НаблюдениеРамкиОкна {
        НаблюдениеРамкиОкна(
            номер: событие.номер,
            x: событие.x,
            y: событие.y,
            ширина: событие.ширина,
            высота: событие.высота,
            единица: событие.единица,

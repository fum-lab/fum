    @Test("Изменение области меняет раскладку без повторного исполнения")
    func resizeНеИсполняетПрограммуПовторно() async throws {
        let фикстура = try размерыОбласти()
        #expect(фикстура.схема == "fuma.сценарий-размеров-контентной-области.1")
        #expect(фикстура.события.count == 2)
        let цикл = ЦиклОператора()

        _ = try await цикл.выполнитьОдинШаг(вход: "ёж", определение: пример())
        let доНаблюдений = await цикл.снимок()
        #expect(доНаблюдений.числоДействийПользователя == 1)
        #expect(доНаблюдений.числоВызововИсполнителя == 1)
        #expect(доНаблюдений.последнийРезультат?.текст == "FUM: ёж")
        #expect(доНаблюдений.история.count == 1)

        let начальныйСнимок = await цикл.наблюдатьКонтентнуюОбласть(
            try наблюдение(фикстура.события[0], из: фикстура))
        #expect(начальныйСнимок.область?.единица == .пункты)
        #expect(начальныйСнимок.область?.источник == .фикстура)
        #expect(начальныйСнимок.область?.событие == .первоначальноеНаблюдение)
        #expect(начальныйСнимок.раскладка?.числоКолонок == 1)

        let снимокПослеИзменения = await цикл.наблюдатьКонтентнуюОбласть(
            try наблюдение(фикстура.события[1], из: фикстура))
        #expect(снимокПослеИзменения.область?.событие == .изменениеРазмера)
        #expect(снимокПослеИзменения.область?.ширина == 900)
        #expect(снимокПослеИзменения.область?.высота == 480)
        #expect(снимокПослеИзменения.раскладка?.числоКолонок == 2)
        #expect(снимокПослеИзменения.раскладка?.компактнаяВысота == true)
        #expect(снимокПослеИзменения.принятоНаблюденийГеометрии == 2)
        #expect(снимокПослеИзменения.отклоненоНаблюденийГеометрии == 0)
        #expect(снимокПослеИзменения.числоДействийПользователя == доНаблюдений.числоДействийПользователя)
        #expect(снимокПослеИзменения.числоВызововИсполнителя == доНаблюдений.числоВызововИсполнителя)
        #expect(снимокПослеИзменения.последнийРезультат == доНаблюдений.последнийРезультат)
        #expect(снимокПослеИзменения.история == доНаблюдений.история)

        var показанноеСостояние = СостояниеЦиклаФУМА()
        показанноеСостояние.применитьЕслиНовее(начальныйСнимок)
        показанноеСостояние.применитьЕслиНовее(снимокПослеИзменения)
        показанноеСостояние.применитьЕслиНовее(начальныйСнимок)
        #expect(снимокПослеИзменения.версия > начальныйСнимок.версия)
        #expect(показанноеСостояние == снимокПослеИзменения)
        #expect(показанноеСостояние.числоДействийПользователя == 1)
        #expect(показанноеСостояние.числоВызововИсполнителя == 1)

        let снимокПослеNaN = await цикл.наблюдатьКонтентнуюОбласть(
            НаблюдениеКонтентнойОбласти(
                номер: 3, ширина: .nan, высота: 480,
                единица: .пункты, источник: .фикстура, событие: .изменениеРазмера))
        #expect(снимокПослеNaN.последняяОшибкаГеометрии == .неКонечныйРазмер)
        #expect(снимокПослеNaN.отклоненоНаблюденийГеометрии == 1)
        #expect(снимокПослеNaN.область == снимокПослеИзменения.область)
        #expect(снимокПослеNaN.раскладка == снимокПослеИзменения.раскладка)

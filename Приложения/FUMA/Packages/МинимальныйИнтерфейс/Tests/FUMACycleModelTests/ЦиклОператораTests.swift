import Foundation
import Testing
@testable import ЦиклОператора

@Suite("Минимальный цикл FUMA", .serialized)
struct ПроверкиЦиклаОператора {
    private let цикл = ЦиклОператора()

    private func пример() throws -> String {
        let тестовыйФайл = URL(fileURLWithPath: #filePath)
        let пакет = тестовыйФайл
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        let путьФикстуры = пакет.appendingPathComponent("Фикстуры/префикс-одного-шага.json")
        return try String(contentsOf: путьФикстуры, encoding: .utf8)
    }

    private func размерыОбласти() throws -> ФикстураРазмеровОбласти {
        let тестовыйФайл = URL(fileURLWithPath: #filePath)
        let пакет = тестовыйФайл
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        let путьФикстуры = пакет.appendingPathComponent("Фикстуры/размер-области.json")
        return try JSONDecoder().decode(ФикстураРазмеровОбласти.self, from: Data(contentsOf: путьФикстуры))
    }

    private func наблюдение(
        _ событие: СобытиеРазмеровФикстуры,
        из фикстуры: ФикстураРазмеровОбласти
    ) throws -> НаблюдениеКонтентнойОбласти {
        let источник = try #require(ИсточникКонтентнойОбласти(rawValue: фикстуры.источник))
        return НаблюдениеКонтентнойОбласти(
            номер: событие.номер,
            ширина: событие.ширина,
            высота: событие.высота,
            единица: фикстуры.единица,
            источник: источник,
            событие: событие.тип
        )
    }

    private struct ФикстураРазмеровОбласти: Decodable {
        let схема: String
        let источник: String
        let единица: ЕдиницаИзмеренияОбласти
        let события: [СобытиеРазмеровФикстуры]
    }

    private struct СобытиеРазмеровФикстуры: Decodable {
        let номер: Int
        let тип: СобытиеНаблюденияРазмеров
        let ширина: Double
        let высота: Double
    }

    @Test("Один шаг возвращает настоящий результат интерпретатора")
    func одинШаг() async throws {
        let результат = try await цикл.выполнитьОдинШаг(вход: "ёж", определение: пример())

        #expect(результат.текст == "FUM: ёж")
        #expect(результат.выполненоОпераций > 0)
        #expect(!результат.хэшНаблюдения.isEmpty)
    }

    @Test("Пустая и многошаговая программы отклоняются до исполнения")
    func числоШагов() async throws {
        let пустая = #"{"схема":"fum.определение-оператора.1","идентификатор":"пусто","версия":1,"правила":[],"шаги":[]}"#
        do {
            _ = try await цикл.выполнитьОдинШаг(вход: "ёж", определение: пустая)
            Issue.record("Пустая программа неожиданно исполнилась.")
        } catch let ошибка as ОшибкаОдногоШага {
            #expect(ошибка == .числоШагов(0))
        }

        let дваШага = #"{"схема":"fum.определение-оператора.1","идентификатор":"два","версия":1,"правила":[],"шаги":[{"идентификатор":"а","оператор":"обрезать","аргументы":{}},{"идентификатор":"б","оператор":"нижний-регистр","аргументы":{}}]}"#
        do {
            _ = try await цикл.выполнитьОдинШаг(вход: "ёж", определение: дваШага)
            Issue.record("Двухшаговая программа неожиданно исполнилась.")
        } catch let ошибка as ОшибкаОдногоШага {
            #expect(ошибка == .числоШагов(2))
        }
    }

    @Test("Составное определение и скрытый оператор отклоняются")
    func безСоставногоИсполнения() async throws {
        let составное = #"{"схема":"fum.определение-оператора.2","идентификатор":"составное","версия":1,"правила":[],"шаги":[{"идентификатор":"а","оператор":"префикс","аргументы":{"текст":"FUM: "}}],"определения":[]}"#
        do {
            _ = try await цикл.выполнитьОдинШаг(вход: "ёж", определение: составное)
            Issue.record("Составное определение неожиданно исполнилось.")
        } catch let ошибка as ОшибкаОдногоШага {
            #expect(ошибка == .неподдержаннаяСхема)
        }

        let повторПравил = #"{"схема":"fum.определение-оператора.1","идентификатор":"повтор","версия":1,"правила":[],"шаги":[{"идентификатор":"а","оператор":"повторить-правила","аргументы":{"правила":[]}}]}"#
        do {
            _ = try await цикл.выполнитьОдинШаг(вход: "ёж", определение: повторПравил)
            Issue.record("Оператор повторного применения неожиданно исполнился.")
        } catch let ошибка as ОшибкаОдногоШага {
            #expect(ошибка == .составнойОператор)
        }
    }

    @Test("Пределы входа и определения возвращают отказ")
    func пределы() async throws {
        let входЗаПределом = String(repeating: "я", count: 2049)
        do {
            _ = try await цикл.выполнитьОдинШаг(вход: входЗаПределом, определение: пример())
            Issue.record("Вход за пределом неожиданно исполнился.")
        } catch let ошибка as ОшибкаОдногоШага {
            #expect(ошибка == .пределВхода)
        }
        let определениеЗаПределом = String(repeating: " ", count: 16_385)
        do {
            _ = try await цикл.выполнитьОдинШаг(вход: "ёж", определение: определениеЗаПределом)
            Issue.record("Определение за пределом неожиданно исполнилось.")
        } catch let ошибка as ОшибкаОдногоШага {
            #expect(ошибка == .пределОпределения)
        }
    }

    @Test("Изменение области меняет раскладку без повторного исполнения")
    func resizeНеИсполняетПрограммуПовторно() async throws {
        let фикстура = try размерыОбласти()
        #expect(фикстура.схема == "fuma.сценарий-размеров-контентной-области.1")
        #expect(фикстура.события.count == 2)
        let цикл = ЦиклОператора()

        _ = try await цикл.выполнитьОдинШаг(вход: "ёж", определение: пример())
        let доНаблюдений = await цикл.снимок()
        #expect(доНаблюдений.числоДействийПользователя == 1)
        #expect(доНаблюдений.числоВызововИсполнителя == 1)
        #expect(доНаблюдений.последнийРезультат?.текст == "FUM: ёж")
        #expect(доНаблюдений.история.count == 1)

        let начальныйСнимок = await цикл.наблюдатьКонтентнуюОбласть(
            try наблюдение(фикстура.события[0], из: фикстура))
        #expect(начальныйСнимок.область?.единица == .пункты)
        #expect(начальныйСнимок.область?.источник == .фикстура)
        #expect(начальныйСнимок.область?.событие == .первоначальноеНаблюдение)
        #expect(начальныйСнимок.раскладка?.числоКолонок == 1)

        let снимокПослеИзменения = await цикл.наблюдатьКонтентнуюОбласть(
            try наблюдение(фикстура.события[1], из: фикстура))
        #expect(снимокПослеИзменения.область?.событие == .изменениеРазмера)
        #expect(снимокПослеИзменения.область?.ширина == 900)
        #expect(снимокПослеИзменения.область?.высота == 480)
        #expect(снимокПослеИзменения.раскладка?.числоКолонок == 2)
        #expect(снимокПослеИзменения.раскладка?.компактнаяВысота == true)
        #expect(снимокПослеИзменения.принятоНаблюденийГеометрии == 2)
        #expect(снимокПослеИзменения.отклоненоНаблюденийГеометрии == 0)
        #expect(снимокПослеИзменения.числоДействийПользователя == доНаблюдений.числоДействийПользователя)
        #expect(снимокПослеИзменения.числоВызововИсполнителя == доНаблюдений.числоВызововИсполнителя)
        #expect(снимокПослеИзменения.последнийРезультат == доНаблюдений.последнийРезультат)
        #expect(снимокПослеИзменения.история == доНаблюдений.история)

        var показанноеСостояние = СостояниеЦиклаФУМА()
        показанноеСостояние.применитьЕслиНовее(начальныйСнимок)
        показанноеСостояние.применитьЕслиНовее(снимокПослеИзменения)
        показанноеСостояние.применитьЕслиНовее(начальныйСнимок)
        #expect(снимокПослеИзменения.версия > начальныйСнимок.версия)
        #expect(показанноеСостояние == снимокПослеИзменения)
        #expect(показанноеСостояние.числоДействийПользователя == 1)
        #expect(показанноеСостояние.числоВызововИсполнителя == 1)

        let снимокПослеNaN = await цикл.наблюдатьКонтентнуюОбласть(
            НаблюдениеКонтентнойОбласти(
                номер: 3, ширина: .nan, высота: 480,
                единица: .пункты, источник: .фикстура, событие: .изменениеРазмера))
        #expect(снимокПослеNaN.последняяОшибкаГеометрии == .неКонечныйРазмер)
        #expect(снимокПослеNaN.отклоненоНаблюденийГеометрии == 1)
        #expect(снимокПослеNaN.область == снимокПослеИзменения.область)
        #expect(снимокПослеNaN.раскладка == снимокПослеИзменения.раскладка)
        #expect(снимокПослеNaN.числоДействийПользователя == доНаблюдений.числоДействийПользователя)
        #expect(снимокПослеNaN.числоВызововИсполнителя == доНаблюдений.числоВызововИсполнителя)
        #expect(снимокПослеNaN.последнийРезультат == доНаблюдений.последнийРезультат)
        #expect(снимокПослеNaN.история == доНаблюдений.история)

        let снимокПослеInf = await цикл.наблюдатьКонтентнуюОбласть(
            НаблюдениеКонтентнойОбласти(
                номер: 4, ширина: 900, высота: .infinity,
                единица: .пункты, источник: .фикстура, событие: .изменениеРазмера))
        #expect(снимокПослеInf.последняяОшибкаГеометрии == .неКонечныйРазмер)
        #expect(снимокПослеInf.отклоненоНаблюденийГеометрии == 2)
        #expect(снимокПослеInf.числоДействийПользователя == доНаблюдений.числоДействийПользователя)
        #expect(снимокПослеInf.числоВызововИсполнителя == доНаблюдений.числоВызововИсполнителя)
        #expect(снимокПослеInf.последнийРезультат == доНаблюдений.последнийРезультат)
        #expect(снимокПослеInf.история == доНаблюдений.история)

        let снимокПослеНуля = await цикл.наблюдатьКонтентнуюОбласть(
            НаблюдениеКонтентнойОбласти(
                номер: 5, ширина: 900, высота: 0,
                единица: .пункты, источник: .фикстура, событие: .изменениеРазмера))
        #expect(снимокПослеНуля.последняяОшибкаГеометрии == .неположительныйРазмер)
        #expect(снимокПослеНуля.отклоненоНаблюденийГеометрии == 3)
        #expect(снимокПослеНуля.область == снимокПослеИзменения.область)
        #expect(снимокПослеНуля.раскладка == снимокПослеИзменения.раскладка)
        #expect(снимокПослеНуля.числоДействийПользователя == доНаблюдений.числоДействийПользователя)
        #expect(снимокПослеНуля.числоВызововИсполнителя == доНаблюдений.числоВызововИсполнителя)
        #expect(снимокПослеНуля.последнийРезультат == доНаблюдений.последнийРезультат)
        #expect(снимокПослеНуля.история == доНаблюдений.история)
    }
}

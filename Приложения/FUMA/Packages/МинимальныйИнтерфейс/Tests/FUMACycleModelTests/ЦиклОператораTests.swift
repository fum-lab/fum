    @MainActor
    @Test("Синхронный владелец вызывает адаптер один раз; рамка окна не повторяет его")
    func клавиатураИРамкаОкна() async throws {
        let fixture = try сценарийКлавиатурыИРамки()
        #expect(fixture.схема == "fuma.сценарий-ввода-и-рамки-окна.1")
        #expect(fixture.идентификаторРаскладки == "qwerty")
        #expect(fixture.наблюденияРамки.count == 2)
        let window = ИдентификаторОкнаВвода(rawValue: UUID())
        let focus = ИдентификаторФокусаВвода(rawValue: UUID())
        let keyboard = ВладелецКлавиатурногоАдаптера()
        #expect(try keyboard.подтвердитьФокус(
            окно: window,
            фокус: focus,
            поколение: 1,
            снимокМодификаторов: .пустое,
            моментНаблюденияНс: 50
        ))

        let key = fixture.событиеКлавиатуры
        #expect(key.обработкаНативнымКраем == "fuma")
        let witness = СвидетельствоСобытияКлавиатуры(
            окно: window,
            фокус: focus,
            поколениеФокуса: 1,
            порядок: 1,
            моментНаблюденияНс: 100
        )
        let event = ФизическоеСобытиеКлавиатуры(
            идентификатор: ИдентификаторСобытияКлавиатуры(rawValue: UUID()),
            свидетельство: witness,
            код: key.код,
            фаза: key.фаза,
            повтор: key.повтор,
            раскладка: .qwerty,
            обработкаНативнымКраем: .fuma,
            снимокМодификаторов: .пустое
        )
        let result = try keyboard.обработатьКлавиатурноеСобытие(event)
        #expect(result.статус == .обработано)
        #expect(result.маршрут == .потребить)
        guard case .текст(let text, источник: .fuma) = result.вывод else {
            Issue.record("Адаптер не вернул текст FUMA.")
            return
        }
        #expect(text == key.ожидаемыйТекст)
        #expect(result.трасса != nil)

        let cycle = ЦиклОператора()
        let afterKey = await cycle.записатьРезультатКлавиатуры(
            СобытиеСРезультатомКлавиатуры(событие: event, результат: result)
        )
        #expect(afterKey.числоДействийПользователя == 0)
        #expect(afterKey.числоВызововИсполнителя == 1)
        #expect(afterKey.историяКлавиатуры.count == 1)

        let firstFrame = try наблюдениеРамки(fixture.наблюденияРамки[0], из: fixture)
        let firstState = await cycle.наблюдатьРамкуОкна(firstFrame)
        #expect(firstState.рамкаОкна?.единица == .пункты)
        #expect(firstState.рамкаОкна?.источник == .фикстура)
        #expect(firstState.рамкаОкна?.событие == .первоначальноеНаблюдение)
        #expect(firstState.рамкаОкна?.x == 80)
        #expect(firstState.область == nil)

        let viewportFixture = try размерыОбласти()
        let viewportFirst = await cycle.наблюдатьКонтентнуюОбласть(
            try наблюдение(viewportFixture.события[0], из: viewportFixture))
        let viewportResized = await cycle.наблюдатьКонтентнуюОбласть(
            try наблюдение(viewportFixture.события[1], из: viewportFixture))
        #expect(viewportResized.область?.ширина == 900)
        #expect(viewportResized.рамкаОкна == viewportFirst.рамкаОкна)

        let resizedFrame = try наблюдениеРамки(fixture.наблюденияРамки[1], из: fixture)
        let afterResize = await cycle.наблюдатьРамкуОкна(resizedFrame)
        #expect(afterResize.рамкаОкна?.x == 120)
        #expect(afterResize.рамкаОкна?.y == 90)
        #expect(afterResize.рамкаОкна?.ширина == 900)

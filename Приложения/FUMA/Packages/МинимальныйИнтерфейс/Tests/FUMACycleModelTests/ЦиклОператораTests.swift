    private func пример() throws -> String {
        let тестовыйФайл = URL(fileURLWithPath: #filePath)
        let пакет = тестовыйФайл
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        let путьФикстуры = пакет.appendingPathComponent("Фикстуры/префикс-одного-шага.json")
        return try String(contentsOf: путьФикстуры, encoding: .utf8)
    }

    private func размерыОбласти() throws -> ФикстураРазмеровОбласти {
        let тестовыйФайл = URL(fileURLWithPath: #filePath)
        let пакет = тестовыйФайл
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        let путьФикстуры = пакет.appendingPathComponent("Фикстуры/размер-области.json")
        return try JSONDecoder().decode(ФикстураРазмеровОбласти.self, from: Data(contentsOf: путьФикстуры))
    }

    private func сценарийКлавиатурыИРамки() throws -> ФикстураКлавиатурыИРамки {
        let тестовыйФайл = URL(fileURLWithPath: #filePath)
        let пакет = тестовыйФайл
            .deletingLastPathComponent()

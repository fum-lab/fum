    @Test("реентерабельная потеря фокуса откладывает отзыв и оставляет исход неизвестным")
    @MainActor
    func реентерабельнаяПотеряФокусаНеТеряется() throws {
        let (владелец, окно, фокус) = try создатьВладельца()
        try принять(владелец, окно: окно, фокус: фокус, идентификатор: UUID(),
                    порядок: 1, текст: "a", выделение: 1..<1)
        let кадр = try владелец.подготовитьТекущуюСекцию()
        var числоЭффектов = 0
        var сменаФокусаОтклонена = false
        var отзывОтложен = false
        var исходНеизвестен = false
        do {
            try владелец.выполнитьТекущуюСекцию(кадр) { _ in
                do {
                    try владелец.подтвердитьФокус(окно: окно, фокус: UUID(), поколение: 2)
                    Issue.record("Смена фокуса прошла во время активного обработчика.")
                } catch ОшибкаПереходаКадра.занято {
                    сменаФокусаОтклонена = true
                }
                отзывОтложен = владелец.отозватьФокус(
                    окно: окно, фокус: фокус, поколение: 1
                ) == .отложен
                // Эффект после отзыва возможен; владелец обязан вернуть UNKNOWN и запретить повтор.
                числоЭффектов += 1
            }
            Issue.record("Отложенный отзыв должен вернуть неизвестный исход без повтора.")
        } catch ОшибкаПереходаКадра.исходНеизвестенПослеИнвалидации {
            исходНеизвестен = true
        } catch {
            Issue.record("Неожиданный исход callback: \(String(reflecting: error))")
        }
        #expect(сменаФокусаОтклонена)
        #expect(отзывОтложен)
        #expect(исходНеизвестен)
        #expect(числоЭффектов == 1)
        #expect(владелец.снимок.текст == "a")
        do {
            try владелец.подтвердитьФокус(окно: окно, фокус: фокус, поколение: 1)
            Issue.record("Отозванное поколение фокуса было принято повторно.")
        } catch ОшибкаПереходаКадра.устарело {
            // Отзыв очищает право, а монотонное поколение окна сохраняется.
        }
        let новыйФокус = UUID()
        try владелец.подтвердитьФокус(окно: окно, фокус: новыйФокус, поколение: 2)
        let новыйВвод = UUID()
        try принять(владелец, окно: окно, фокус: новыйФокус, поколениеФокуса: 2,
                    идентификатор: новыйВвод, порядок: 1, текст: "ab", выделение: 2..<2)
        #expect(владелец.снимок.текст == "ab")
        #expect(владелец.снимок.ревизияТекста == 2)
        #expect(владелец.снимок.последнийИзменившийТекстВвод == новыйВвод)
        do {
            _ = try владелец.подготовитьТекущуюСекцию()
            Issue.record("Новый кадр разрешён после sticky UNKNOWN.")
        } catch ОшибкаПереходаКадра.исходНеизвестен {
            // До отдельно разрешённого восстановления новый внешний эффект закрыт.
        }
        var повторныйЭффект = 0
        do {
            try владелец.выполнитьТекущуюСекцию(кадр) { _ in повторныйЭффект += 1 }
            Issue.record("Старая секция была повторно исполнена после UNKNOWN.")
        } catch ОшибкаПереходаКадра.исходНеизвестен {
            // Sticky UNKNOWN запрещает повтор и со старым, и с новым фокусом.
        }
        #expect(повторныйЭффект == 0)
    }


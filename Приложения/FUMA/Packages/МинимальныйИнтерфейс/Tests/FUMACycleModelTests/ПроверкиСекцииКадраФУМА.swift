                    порядок: 2, текст: "ab", выделение: 2..<2)
        try принять(владелец, окно: окно, фокус: фокус, идентификатор: идентификаторПробела,
                    порядок: 3, текст: "ab ", выделение: 3..<3)

        var кадрРезультат: КадрБитмаповФУМА?

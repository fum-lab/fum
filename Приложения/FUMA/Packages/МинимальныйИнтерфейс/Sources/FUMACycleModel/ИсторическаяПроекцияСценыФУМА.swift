import Foundation

/// Стабильная объектная метка одного экземпляра владельца; кадр удерживает её,
/// поэтому адрес метки не переиспользуется, пока кадр существует.
final class СфераВладельцаКадра: Sendable {}

/// Неизменяемая копия одного снимка. Сама по себе не удостоверяет свежесть и не даёт
/// права на внешний эффект; контролем владельца метод создаёт её в своей синхронной секции.
public struct ИсторическаяПроекцияСценыФУМА: Sendable, Equatable {
    fileprivate let сфера: СфераВладельцаКадра
    public let слой: UUID
    public let эпоха: UUID
    public let идентификаторОкна: UUID?
    public let идентификаторФокуса: UUID?
    public let поколениеФокуса: UInt64?
    public let ревизияТекста: Int
    public let ревизияСцены: Int
    public let выделениеUTF16: Range<Int>
    public let идентификаторВводаСцены: UUID
    public let идентификаторПоследнегоИзмененияТекста: UUID?
    public let точныеБайтыUTF8: [UInt8]
    public let скалярыUnicode: [UInt32]

    /// Для открытого исторического чтения токен создаётся локально и не совпадёт
    /// с токеном текущего владельца; такой кадр нельзя передать через метод владельца.
    public init(снимок: СнимокТекстаСценыФУМА) throws {
        try self.init(снимок: снимок, сфера: СфераВладельцаКадра())
    }

    init(
        снимок: СнимокТекстаСценыФУМА,
        сфера: СфераВладельцаКадра,
        окно: UUID? = nil,
        фокус: UUID? = nil,
        поколениеФокуса: UInt64? = nil
    ) throws {
        guard let слой = снимок.слой, let эпоха = снимок.эпоха,
              let ввод = снимок.последнийВводСцены else {
            throw ОшибкаПроекцииСценыФУМА.нетПричинногоКонтекста
        }
        let байты = Array(снимок.текст.utf8)
        guard байты.count <= 4096 else {
            throw ОшибкаПроекцииСценыФУМА.пределТекста
        }
        let длинаUTF16 = (снимок.текст as NSString).length
        guard снимок.выделениеUTF16.lowerBound >= 0,
              снимок.выделениеUTF16.lowerBound <= снимок.выделениеUTF16.upperBound,
              снимок.выделениеUTF16.upperBound <= длинаUTF16 else {
            throw ОшибкаПроекцииСценыФУМА.недопустимоеВыделение
        }
        self.сфера = сфера
        self.слой = слой
        self.эпоха = эпоха
        self.идентификаторОкна = окно
        self.идентификаторФокуса = фокус
        self.поколениеФокуса = поколениеФокуса
        self.ревизияТекста = снимок.ревизияТекста
        self.ревизияСцены = снимок.ревизияСцены
        self.выделениеUTF16 = снимок.выделениеUTF16
        self.идентификаторВводаСцены = ввод
        self.идентификаторПоследнегоИзмененияТекста = снимок.последнийИзменившийТекстВвод
        self.точныеБайтыUTF8 = байты
        self.скалярыUnicode = снимок.текст.unicodeScalars.map(\.value)
    }

    public static func == (левая: Self, правая: Self) -> Bool {
        левая.сфера === правая.сфера && левая.слой == правая.слой && левая.эпоха == правая.эпоха &&
        левая.идентификаторОкна == правая.идентификаторОкна &&
        левая.идентификаторФокуса == правая.идентификаторФокуса &&
        левая.поколениеФокуса == правая.поколениеФокуса &&
        левая.ревизияТекста == правая.ревизияТекста && левая.ревизияСцены == правая.ревизияСцены &&
        левая.выделениеUTF16 == правая.выделениеUTF16 &&
        левая.идентификаторВводаСцены == правая.идентификаторВводаСцены &&
        левая.идентификаторПоследнегоИзмененияТекста == правая.идентификаторПоследнегоИзмененияТекста &&
        левая.точныеБайтыUTF8.elementsEqual(правая.точныеБайтыUTF8) &&
        левая.скалярыUnicode == правая.скалярыUnicode
    }
}

public enum ОшибкаПроекцииСценыФУМА: Error, Equatable, Sendable {
    case нетПричинногоКонтекста
    case пределТекста
    case недопустимоеВыделение
}

public struct ФикстураБитмаповФУМА: Decodable, Sendable {
    public struct Решётка: Decodable, Sendable {
        public let высота: Int
        public let строкаСверхуВниз: Bool
        public let чернила: [UInt8]
        public let фон: [UInt8]
    }

    public struct Глиф: Decodable, Sendable {
        public let скаляр: String
        public let ширина: Int
        public let продвижение: Int
        public let строки: [String]
    }

    public let решётка: Решётка
    public let глифы: [Глиф]

    public static func загрузитьОткрытую() throws -> Self {
        guard let адрес = Bundle.module.url(forResource: "битмапы-а-б-пробел", withExtension: "json") else {
            throw ОшибкаКомпозицииБитмаповФУМА.недоступнаФикстура
        }
        let атрибуты = try FileManager.default.attributesOfItem(atPath: адрес.path)
        guard let размер = атрибуты[.size] as? NSNumber,
              размер.intValue > 0, размер.intValue <= 16_384 else {
            throw ОшибкаКомпозицииБитмаповФУМА.недопустимаяФикстура
        }
        let данные = try Data(contentsOf: адрес)
        guard данные.count == размер.intValue else {
            throw ОшибкаКомпозицииБитмаповФУМА.недопустимаяФикстура
        }
        return try JSONDecoder().decode(Self.self, from: данные)
    }
}

/// Пиксели и происхождение одной проекции. Метаданные связывают кадр с владельца и ревизии,
/// но не подтверждают отправку буфера на отображение или наблюдаемое представление.
public struct КадрБитмаповФУМА: Sendable, Equatable {
    fileprivate let сфера: СфераВладельцаКадра
    public let слой: UUID
    public let эпоха: UUID
    public let идентификаторОкна: UUID?
    public let идентификаторФокуса: UUID?
    public let поколениеФокуса: UInt64?
    public let ширина: Int
    public let высота: Int
    public let шагСтрокиБайт: Int
    public let пиксели: [UInt8]
    public let строкиЧернил: [String]
    public let байтыИсходногоТекста: [UInt8]
    public let ревизияТекста: Int
    public let ревизияСцены: Int
    public let выделениеUTF16: Range<Int>
    public let идентификаторВводаСцены: UUID
    public let идентификаторПоследнегоИзмененияТекста: UUID?

    func соответствует(_ проекции: ИсторическаяПроекцияСценыФУМА) -> Bool {
        сфера === проекции.сфера && слой == проекции.слой && эпоха == проекции.эпоха &&
        идентификаторОкна == проекции.идентификаторОкна &&
        идентификаторФокуса == проекции.идентификаторФокуса &&
        поколениеФокуса == проекции.поколениеФокуса &&
        байтыИсходногоТекста.elementsEqual(проекции.точныеБайтыUTF8) &&
        ревизияТекста == проекции.ревизияТекста && ревизияСцены == проекции.ревизияСцены &&
        выделениеUTF16 == проекции.выделениеUTF16 &&
        идентификаторВводаСцены == проекции.идентификаторВводаСцены &&
        идентификаторПоследнегоИзмененияТекста == проекции.идентификаторПоследнегоИзмененияТекста
    }

    public static func == (левая: Self, правая: Self) -> Bool {
        левая.сфера === правая.сфера && левая.слой == правая.слой && левая.эпоха == правая.эпоха &&
        левая.идентификаторОкна == правая.идентификаторОкна &&
        левая.идентификаторФокуса == правая.идентификаторФокуса &&
        левая.поколениеФокуса == правая.поколениеФокуса &&
        левая.ширина == правая.ширина && левая.высота == правая.высота &&
        левая.шагСтрокиБайт == правая.шагСтрокиБайт && левая.пиксели == правая.пиксели &&
        левая.строкиЧернил == правая.строкиЧернил &&
        левая.байтыИсходногоТекста.elementsEqual(правая.байтыИсходногоТекста) &&
        левая.ревизияТекста == правая.ревизияТекста && левая.ревизияСцены == правая.ревизияСцены &&
        левая.выделениеUTF16 == правая.выделениеUTF16 &&
        левая.идентификаторВводаСцены == правая.идентификаторВводаСцены &&
        левая.идентификаторПоследнегоИзмененияТекста == правая.идентификаторПоследнегоИзмененияТекста
    }
}

/// Композитор только для открытой собственной bitmap fixture.
/// Не Synthax/SFNT, не shaping и не Metal submitter.
public enum КомпозиторБитмаповФУМА {
    private static let пределШирины = 4096
    private static let пределВысоты = 512
    private static let пределПлощади = 1_048_576

    public static func собрать(
        _ проекция: ИсторическаяПроекцияСценыФУМА,
        по фикстуре: ФикстураБитмаповФУМА
    ) throws -> КадрБитмаповФУМА {
        guard фикстура.решётка.строкаСверхуВниз,
              фикстура.решётка.высота > 0,
              фикстура.решётка.высота <= пределВысоты,
              фикстура.решётка.чернила.count == 4,
              фикстура.решётка.фон.count == 4 else {
            throw ОшибкаКомпозицииБитмаповФУМА.недопустимаяФикстура
        }
        guard !фикстура.глифы.isEmpty, фикстура.глифы.count <= 32 else {
            throw ОшибкаКомпозицииБитмаповФУМА.пределКадра
        }
        guard let текст = String(bytes: проекция.точныеБайтыUTF8, encoding: .utf8),
              проекция.скалярыUnicode == текст.unicodeScalars.map(\.value) else {
            throw ОшибкаКомпозицииБитмаповФУМА.несогласованнаяПроекция
        }
        guard !текст.unicodeScalars.isEmpty else {
            throw ОшибкаКомпозицииБитмаповФУМА.пустаяСценаНеПоддержана
        }
        guard фикстура.глифы.allSatisfy({
            $0.скаляр.utf8.count <= 4 && $0.скаляр.unicodeScalars.count == 1
        }) else {
            throw ОшибкаКомпозицииБитмаповФУМА.недопустимаяФикстура
        }
        for индекс in фикстура.глифы.indices {
            for другойИндекс in фикстура.глифы.indices where другойИндекс > индекс {
                guard !фикстура.глифы[индекс].скаляр.utf8.elementsEqual(
                    фикстура.глифы[другойИндекс].скаляр.utf8
                ) else {
                    throw ОшибкаКомпозицииБитмаповФУМА.недопустимаяФикстура
                }
            }
        }

        var размещения: [(ФикстураБитмаповФУМА.Глиф, Int)] = []
        var ширина = 0
        for скаляр in текст.unicodeScalars {
            let ключ = String(скаляр)
            guard let глиф = фикстура.глифы.first(where: {
                $0.скаляр.utf8.elementsEqual(ключ.utf8)
            }) else {
                throw ОшибкаКомпозицииБитмаповФУМА.неподдержанныйСкаляр
            }
            guard глиф.ширина > 0, глиф.ширина <= пределШирины,
                  глиф.продвижение >= глиф.ширина, глиф.продвижение <= пределШирины,
                  глиф.строки.count == фикстура.решётка.высота,
                  глиф.строки.allSatisfy({
                      $0.utf8.count == глиф.ширина && $0.utf8.allSatisfy { $0 == 48 || $0 == 49 }
                  }) else {
                throw ОшибкаКомпозицииБитмаповФУМА.недопустимаяФикстура
            }
            let (следующаяШирина, переполнение) = ширина.addingReportingOverflow(глиф.продвижение)
            guard !переполнение, следующаяШирина <= пределШирины else {
                throw ОшибкаКомпозицииБитмаповФУМА.пределКадра
            }
            размещения.append((глиф, ширина))
            ширина = следующаяШирина
        }
        let высота = фикстура.решётка.высота
        let (площадь, переполнениеПлощади) = ширина.multipliedReportingOverflow(by: высота)
        guard !переполнениеПлощади, площадь <= пределПлощади else {
            throw ОшибкаКомпозицииБитмаповФУМА.пределКадра
        }
        let (объём, переполнениеОбъёма) = площадь.multipliedReportingOverflow(by: 4)
        guard !переполнениеОбъёма, объём <= пределПлощади * 4 else {
            throw ОшибкаКомпозицииБитмаповФУМА.пределКадра
        }

        var строки = Array(repeating: Array(repeating: Character("0"), count: ширина), count: высота)
        for (глиф, начало) in размещения {
            for (номерСтроки, строка) in глиф.строки.enumerated() {
                for (номерСтолбца, пиксель) in строка.enumerated() where пиксель == "1" {
                    строки[номерСтроки][начало + номерСтолбца] = "1"
                }
            }
        }
        var пиксели: [UInt8] = []
        пиксели.reserveCapacity(объём)
        for строка in строки {
            for пиксель in строка {
                пиксели.append(contentsOf: пиксель == "1" ? фикстура.решётка.чернила : фикстура.решётка.фон)
            }
        }
        let (шагСтроки, переполнениеШага) = ширина.multipliedReportingOverflow(by: 4)
        guard !переполнениеШага else { throw ОшибкаКомпозицииБитмаповФУМА.пределКадра }
        return КадрБитмаповФУМА(
            сфера: проекция.сфера,
            слой: проекция.слой,
            эпоха: проекция.эпоха,
            идентификаторОкна: проекция.идентификаторОкна,
            идентификаторФокуса: проекция.идентификаторФокуса,
            поколениеФокуса: проекция.поколениеФокуса,
            ширина: ширина,
            высота: высота,
            шагСтрокиБайт: шагСтроки,
            пиксели: пиксели,
            строкиЧернил: строки.map(String.init),
            байтыИсходногоТекста: проекция.точныеБайтыUTF8,
            ревизияТекста: проекция.ревизияТекста,
            ревизияСцены: проекция.ревизияСцены,
            выделениеUTF16: проекция.выделениеUTF16,
            идентификаторВводаСцены: проекция.идентификаторВводаСцены,
            идентификаторПоследнегоИзмененияТекста: проекция.идентификаторПоследнегоИзмененияТекста
        )
    }
}

public enum ОшибкаКомпозицииБитмаповФУМА: Error, Equatable, Sendable {
    case недоступнаФикстура
    case недопустимаяФикстура
    case несогласованнаяПроекция
    case пустаяСценаНеПоддержана
    case неподдержанныйСкаляр
    case пределКадра
}

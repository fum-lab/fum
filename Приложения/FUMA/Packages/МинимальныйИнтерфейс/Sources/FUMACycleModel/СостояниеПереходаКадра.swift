import Foundation

/// Встраивается единственным владельцем окна; не получает события и не исполняет граф.
struct СнимокПереходаКадра: Equatable, Sendable {
    let эпоха: UUID
    let слой: UUID
    let текст: String
    let выделение: Range<Int>
    let ревизияТекста: Int
    let ревизияСцены: Int
    let последнийИзменившийТекстВвод: UUID?
    let последнийВводСцены: UUID?
    let сценаОтВвода: Bool
}

struct СобытиеПереходаКадра: Sendable {
    let эпоха: UUID
    let идентификатор: UUID
    let порядок: UInt64
}

struct РезервПереходаКадра: Equatable, Sendable {
    fileprivate let эпоха: UUID
    fileprivate let слой: UUID
    fileprivate let номер: UInt64
    fileprivate let ввод: UUID
    fileprivate let ревизияТекста: Int
    fileprivate let ревизияСцены: Int
}

enum ОшибкаПереходаКадра: Error, Equatable {
    case занято
    case устарело
    case повтор
    case неверныйПорядок
    case пределИстории
    case неверноеВыделениеИлиРазмер
    case невернаяРевизия
    case пределРевизии
    case переполнение
    case нетПричинногоВвода
    case резервУжеЕсть
    case секцияСценыУжеПотреблена
    case исходНеизвестен
}

enum РезультатВводаПерехода: Equatable {
    case изменено
    case безИзменений
}

/// Факт возврата callback; отправка и представление здесь не наблюдаются.
enum РезультатСекцииПерехода: Equatable {
    case секцияПотреблена
}

/// Объект принадлежит только МодельОкна и хранит единственную копию этих данных.
/// Все входы — результаты уже допущенного владельцем события и оператора FUMA.
@MainActor
final class СостояниеПереходаКадра {
    /// Общая граница с ПреобразовательМаскиВКадр и графом маски.
    static let предельнаяРевизия = 2_147_483_647
    private(set) var снимок: СнимокПереходаКадра
    private var последнийПорядок: UInt64 = 0
    private var принятыеВводы: Set<UUID> = []
    private var номерКадра: UInt64 = 0
    private var резерв: РезервПереходаКадра?
    private var последняяСценаСПотреблённойСекцией: Int?
    private var неизвестныйИсход = false
    private var секцияАктивна = false
    private let пределСобытий = 4096

    /// Ненулевые начальные значения нужны только для синтетической проверки границ;
    /// вызывающий обязан обеспечить неповторную эпоху. Восстановление не реализовано.
    init(эпоха: UUID, слой: UUID, текст: String = "", выделение: Range<Int> = 0..<0,
         ревизияТекста: Int = 0, ревизияСцены: Int = 0, начальныйНомерКадра: UInt64 = 0) throws {
        guard ревизияТекста >= 0, ревизияСцены >= 0 else {
            throw ОшибкаПереходаКадра.невернаяРевизия
        }
        guard ревизияТекста <= Self.предельнаяРевизия,
              ревизияСцены <= Self.предельнаяРевизия else {
            throw ОшибкаПереходаКадра.пределРевизии
        }
        guard Self.допустимо(текст: текст, выделение: выделение) else {
            throw ОшибкаПереходаКадра.неверноеВыделениеИлиРазмер
        }
        снимок = СнимокПереходаКадра(
            эпоха: эпоха, слой: слой, текст: текст, выделение: выделение,
            ревизияТекста: ревизияТекста, ревизияСцены: ревизияСцены,
            последнийИзменившийТекстВвод: nil, последнийВводСцены: nil, сценаОтВвода: false)
        номерКадра = начальныйНомерКадра
    }

    /// Результат операции вычисляется снаружи; здесь принимается только на той же основе.
    func принять(_ событие: СобытиеПереходаКадра, на основа: СнимокПереходаКадра,
                 текст: String, выделение: Range<Int>) throws -> РезультатВводаПерехода {
        try проверитьДоступ()
        guard событие.эпоха == снимок.эпоха, таЖеОснова(основа) else {
            throw ОшибкаПереходаКадра.устарело
        }
        guard !принятыеВводы.contains(событие.идентификатор) else {
            throw ОшибкаПереходаКадра.повтор
        }
        guard событие.порядок > последнийПорядок else { throw ОшибкаПереходаКадра.неверныйПорядок }
        guard принятыеВводы.count < пределСобытий else { throw ОшибкаПереходаКадра.пределИстории }
        guard Self.допустимо(текст: текст, выделение: выделение) else {
            throw ОшибкаПереходаКадра.неверноеВыделениеИлиРазмер
        }
        let текстИзменён = !текст.utf8.elementsEqual(снимок.текст.utf8)
        let сценаИзменена = текстИзменён || выделение != снимок.выделение
        let новаяРевизияТекста = снимок.ревизияТекста.addingReportingOverflow(текстИзменён ? 1 : 0)
        let новаяРевизияСцены = снимок.ревизияСцены.addingReportingOverflow(сценаИзменена ? 1 : 0)
        guard !новаяРевизияТекста.overflow, !новаяРевизияСцены.overflow else {
            throw ОшибкаПереходаКадра.переполнение
        }
        guard новаяРевизияТекста.partialValue <= Self.предельнаяРевизия,
              новаяРевизияСцены.partialValue <= Self.предельнаяРевизия else {
            throw ОшибкаПереходаКадра.пределРевизии
        }
        принятыеВводы.insert(событие.идентификатор)
        последнийПорядок = событие.порядок
        guard сценаИзменена else { return .безИзменений }
        снимок = СнимокПереходаКадра(
            эпоха: снимок.эпоха, слой: снимок.слой, текст: текст, выделение: выделение,
            ревизияТекста: новаяРевизияТекста.partialValue, ревизияСцены: новаяРевизияСцены.partialValue,
            последнийИзменившийТекстВвод: текстИзменён ? событие.идентификатор : снимок.последнийИзменившийТекстВвод,
            последнийВводСцены: событие.идентификатор, сценаОтВвода: true)
        резерв = nil
        return .изменено
    }

    /// Копия только для транзакционного перехода контекста. История ID не
    /// вытесняется; резерв/состояние отказа копируются целиком.
    fileprivate func копияДляПерехода() throws -> Self {
        try проверитьДоступ()
        let копия = try Self(
            эпоха: снимок.эпоха,
            слой: снимок.слой,
            текст: снимок.текст,
            выделение: снимок.выделение,
            ревизияТекста: снимок.ревизияТекста,
            ревизияСцены: снимок.ревизияСцены,
            начальныйНомерКадра: номерКадра
        )
        копия.последнийПорядок = последнийПорядок
        копия.принятыеВводы = принятыеВводы
        копия.резерв = резерв
        копия.последняяСценаСПотреблённойСекцией = последняяСценаСПотреблённойСекцией
        копия.неизвестныйИсход = неизвестныйИсход
        копия.снимок = снимок
        return копия
    }

    /// Смена фокуса сбрасывает только watermark порядка текущей эпохи. Множество
    /// ID событий и авторитетные текст с ревизиями остаются в этом владельце.
    func начатьЭпоху(_ новаяЭпоха: UUID) throws {
        try проверитьДоступ()
        guard резерв == nil else { throw ОшибкаПереходаКадра.занято }
        guard новаяЭпоха != снимок.эпоха else { return }
        снимок = СнимокПереходаКадра(
            эпоха: новаяЭпоха,
            слой: снимок.слой,
            текст: снимок.текст,
            выделение: снимок.выделение,
            ревизияТекста: снимок.ревизияТекста,
            ревизияСцены: снимок.ревизияСцены,
            последнийИзменившийТекстВвод: снимок.последнийИзменившийТекстВвод,
            последнийВводСцены: снимок.последнийВводСцены,
            сценаОтВвода: снимок.сценаОтВвода
        )
        последнийПорядок = 0
    }

    /// Размер и иные внешние причины определяются вызывающим; этот срез их не растеризует.
    func изменитьВнешнююСцену(на основа: СнимокПереходаКадра, изменено: Bool) throws {
        try проверитьДоступ()
        guard таЖеОснова(основа) else { throw ОшибкаПереходаКадра.устарело }
        guard изменено else { return }
        let новаяРевизия = снимок.ревизияСцены.addingReportingOverflow(1)
        guard !новаяРевизия.overflow else { throw ОшибкаПереходаКадра.переполнение }
        guard новаяРевизия.partialValue <= Self.предельнаяРевизия else {
            throw ОшибкаПереходаКадра.пределРевизии
        }
        снимок = СнимокПереходаКадра(
            эпоха: снимок.эпоха, слой: снимок.слой, текст: снимок.текст, выделение: снимок.выделение,
            ревизияТекста: снимок.ревизияТекста, ревизияСцены: новаяРевизия.partialValue,
            последнийИзменившийТекстВвод: снимок.последнийИзменившийТекстВвод,
            последнийВводСцены: nil, сценаОтВвода: false)
        резерв = nil
    }

    /// Одна потреблённая секция на ревизию сцены; реальные пиксели не создаются.
    func зарезервировать(на основа: СнимокПереходаКадра) throws -> РезервПереходаКадра {
        try проверитьДоступ()
        guard !неизвестныйИсход else { throw ОшибкаПереходаКадра.исходНеизвестен }
        guard таЖеОснова(основа) else { throw ОшибкаПереходаКадра.устарело }
        guard резерв == nil else { throw ОшибкаПереходаКадра.резервУжеЕсть }
        guard последняяСценаСПотреблённойСекцией != снимок.ревизияСцены else {
            throw ОшибкаПереходаКадра.секцияСценыУжеПотреблена
        }
        guard снимок.сценаОтВвода, let ввод = снимок.последнийВводСцены else {
            throw ОшибкаПереходаКадра.нетПричинногоВвода
        }
        let следующий = номерКадра.addingReportingOverflow(1)
        guard !следующий.overflow else { throw ОшибкаПереходаКадра.переполнение }
        let новый = РезервПереходаКадра(
            эпоха: снимок.эпоха, слой: снимок.слой, номер: следующий.partialValue,
            ввод: ввод, ревизияТекста: снимок.ревизияТекста, ревизияСцены: снимок.ревизияСцены)
        номерКадра = следующий.partialValue
        резерв = новый
        return новый
    }

    /// Действие предназначено для callback стыка v3; его возврат не доказывает отправку.
    /// Любая ошибка действия необратимо помечается UNKNOWN; никакого await.
    @discardableResult
    func выполнить(_ предложенный: РезервПереходаКадра,
                   действие: @MainActor (СнимокПереходаКадра) throws -> Void) throws -> РезультатСекцииПерехода {
        try проверитьДоступ()
        guard !неизвестныйИсход else { throw ОшибкаПереходаКадра.исходНеизвестен }
        guard резерв == предложенный,
              предложенный.эпоха == снимок.эпоха, предложенный.слой == снимок.слой,
              предложенный.ввод == снимок.последнийВводСцены,
              предложенный.ревизияТекста == снимок.ревизияТекста,
              предложенный.ревизияСцены == снимок.ревизияСцены else {
            throw ОшибкаПереходаКадра.устарело
        }
        секцияАктивна = true
        defer { секцияАктивна = false }
        do {
            try действие(снимок)
            последняяСценаСПотреблённойСекцией = предложенный.ревизияСцены
            резерв = nil
            return .секцияПотреблена
        } catch {
            неизвестныйИсход = true
            резерв = nil
            throw ОшибкаПереходаКадра.исходНеизвестен
        }
    }

    private func проверитьДоступ() throws {
        guard !секцияАктивна else { throw ОшибкаПереходаКадра.занято }
    }

    private func таЖеОснова(_ основа: СнимокПереходаКадра) -> Bool {
        основа.эпоха == снимок.эпоха && основа.слой == снимок.слой &&
        основа.ревизияТекста == снимок.ревизияТекста && основа.ревизияСцены == снимок.ревизияСцены &&
        основа.последнийИзменившийТекстВвод == снимок.последнийИзменившийТекстВвод &&
        основа.последнийВводСцены == снимок.последнийВводСцены &&
        основа.сценаОтВвода == снимок.сценаОтВвода && основа.выделение == снимок.выделение &&
        основа.текст.utf8.elementsEqual(снимок.текст.utf8)
    }

    private static func допустимо(текст: String, выделение: Range<Int>) -> Bool {
        guard текст.utf8.count <= 4096, выделение.lowerBound >= 0 else { return false }
        guard выделение.upperBound <= текст.utf16.count else { return false }
        // Допускаем только границы Character: ни разрыв суррогатной пары,
        // ни разрыв составного пользовательского символа не проходит.
        func граница(_ смещение: Int) -> Bool {
            if смещение == текст.utf16.count { return true }
            return текст.indices.contains { $0.utf16Offset(in: текст) == смещение }
        }
        return граница(выделение.lowerBound) && граница(выделение.upperBound)
    }
}

/// Узкая публичная граница для UI target. Внутренний reducer v3 остаётся единственным
/// владельцем текста, выделения и ревизий; это значение — только снимок чтения.
public struct СнимокТекстаСценыФУМА: Equatable, Sendable {
    public let текст: String
    public let выделениеUTF16: Range<Int>
    public let ревизияТекста: Int
    public let ревизияСцены: Int
    public let последнийИзменившийТекстВвод: UUID?
    public let последнийВводСцены: UUID?
}

public enum РезультатПринятияТекстаФУМА: Equatable, Sendable {
    case изменено
    case безИзменений
}

/// Общее решение UI-проекции и теста: сравнение Swift String не гарантирует
/// побайтное совпадение Unicode-нормальных форм.
public enum ПроекцияТекстаОкнаФУМА {
    public static func значениеДляОбновления(текущее: String, авторитетное: String) -> String? {
        отличаетсяПоUTF8(текущее, от: авторитетное) ? авторитетное : nil
    }

    private static func отличаетсяПоUTF8(_ текущее: String, от авторитетного: String) -> Bool {
        !текущее.utf8.elementsEqual(авторитетное.utf8)
    }
}

public struct ТокенПривязкиВидаФУМА: Hashable, Sendable {
    fileprivate let значение: UUID
}

/// Не позволяет отложенным callback старого NSView менять состояние нового.
@MainActor
public final class ВладелецПривязкиВидаФУМА {
    private weak var объект: AnyObject?
    private var токен: ТокенПривязкиВидаФУМА?

    public init() {}

    @discardableResult
    public func привязать(_ view: AnyObject) -> ТокенПривязкиВидаФУМА {
        if объект === view, let токен { return токен }
        let новый = ТокенПривязкиВидаФУМА(значение: UUID())
        объект = view
        токен = новый
        return новый
    }

    public func являетсяТекущей(_ токен: ТокенПривязкиВидаФУМА, для view: AnyObject) -> Bool {
        self.токен == токен && объект === view
    }

    public func текущаяПривязка(для view: AnyObject) -> ТокенПривязкиВидаФУМА? {
        guard объект === view else { return nil }
        return токен
    }
}

/// Модель окна владеет фасадом и применяет только уже принятый результат FUMA.
@MainActor
public final class ВладелецТекстаСценыФУМА {
    private struct КонтекстФокуса: Equatable {
        let окно: UUID
        let фокус: UUID
        let поколение: UInt64
    }

    private let слой: UUID
    private var контекстФокуса: КонтекстФокуса?
    private var состояние: СостояниеПереходаКадра?
    private var установленноеОкно: UUID?
    private var подтверждённыйФокус: КонтекстФокуса?
    private var поколениеПоОкнам: [UUID: UInt64] = [:]
    private let пределОкон = 4096

    public init(слой: UUID = UUID()) {
        self.слой = слой
    }

    /// Окно устанавливает жизненный цикл собственного NSView до физической клавиши.
    /// Каждое новое окно получает отдельную шкалу поколений и сессию событий.
    public func установитьОкно(_ окно: UUID?) throws {
        guard окно != установленноеОкно else { return }
        if let окно, поколениеПоОкнам[окно] == nil {
            guard поколениеПоОкнам.count < пределОкон else {
                throw ОшибкаПереходаКадра.пределИстории
            }
            поколениеПоОкнам[окно] = 0
        }
        установленноеОкно = окно
        подтверждённыйФокус = nil
    }

    /// Фокус устанавливается только из NSView first-responder callback, отдельно
    /// от клавиши. Поколения монотонны внутри конкретного окна.
    public func подтвердитьФокус(окно: UUID, фокус: UUID, поколение: UInt64) throws {
        guard установленноеОкно == окно, let прежнее = поколениеПоОкнам[окно] else {
            throw ОшибкаПереходаКадра.устарело
        }
        if let текущий = подтверждённыйФокус,
           текущий.окно == окно, текущий.фокус == фокус, текущий.поколение == поколение {
            return
        }
        guard поколение > прежнее else { throw ОшибкаПереходаКадра.устарело }
        поколениеПоОкнам[окно] = поколение
        подтверждённыйФокус = КонтекстФокуса(окно: окно, фокус: фокус, поколение: поколение)
    }

    public func отозватьФокус(окно: UUID, фокус: UUID, поколение: UInt64) {
        guard let текущий = подтверждённыйФокус,
              текущий.окно == окно, текущий.фокус == фокус, текущий.поколение == поколение else {
            return
        }
        подтверждённыйФокус = nil
    }

    public var снимок: СнимокТекстаСценыФУМА {
        guard let состояние else {
            return СнимокТекстаСценыФУМА(
                текст: "", выделениеUTF16: 0..<0, ревизияТекста: 0, ревизияСцены: 0,
                последнийИзменившийТекстВвод: nil, последнийВводСцены: nil
            )
        }
        let снимок = состояние.снимок
        return СнимокТекстаСценыФУМА(
            текст: снимок.текст,
            выделениеUTF16: снимок.выделение,
            ревизияТекста: снимок.ревизияТекста,
            ревизияСцены: снимок.ревизияСцены,
            последнийИзменившийТекстВвод: снимок.последнийИзменившийТекстВвод,
            последнийВводСцены: снимок.последнийВводСцены
        )
    }

    @discardableResult
    public func принять(
        идентификаторОкна: UUID,
        идентификаторФокуса: UUID,
        поколениеФокуса: UInt64,
        идентификаторСобытия: UUID,
        порядок: UInt64,
        текст: String,
        выделениеUTF16: Range<Int>
    ) throws -> РезультатПринятияТекстаФУМА {
        let новыйКонтекст = КонтекстФокуса(
            окно: идентификаторОкна,
            фокус: идентификаторФокуса,
            поколение: поколениеФокуса
        )
        guard установленноеОкно == идентификаторОкна, подтверждённыйФокус == новыйКонтекст else {
            throw ОшибкаПереходаКадра.устарело
        }
        if let текущаяСостояние = состояние, let текущийКонтекст = контекстФокуса {
            guard новыйКонтекст == текущийКонтекст else {
                let кандидат = try текущаяСостояние.копияДляПерехода()
                try кандидат.начатьЭпоху(UUID())
                let результат = try Self.применить(
                    кандидат,
                    идентификаторСобытия: идентификаторСобытия,
                    порядок: порядок,
                    текст: текст,
                    выделениеUTF16: выделениеUTF16
                )
                состояние = кандидат
                контекстФокуса = новыйКонтекст
                return результат
            }
            return try Self.применить(
                текущаяСостояние,
                идентификаторСобытия: идентификаторСобытия,
                порядок: порядок,
                текст: текст,
                выделениеUTF16: выделениеUTF16
            )
        }

        let кандидат = try СостояниеПереходаКадра(эпоха: UUID(), слой: слой)
        let результат = try Self.применить(
            кандидат,
            идентификаторСобытия: идентификаторСобытия,
            порядок: порядок,
            текст: текст,
            выделениеUTF16: выделениеUTF16
        )
        состояние = кандидат
        контекстФокуса = новыйКонтекст
        return результат
    }

    private static func применить(
        _ состояние: СостояниеПереходаКадра,
        идентификаторСобытия: UUID,
        порядок: UInt64,
        текст: String,
        выделениеUTF16: Range<Int>
    ) throws -> РезультатПринятияТекстаФУМА {
        let событие = СобытиеПереходаКадра(
            эпоха: состояние.снимок.эпоха,
            идентификатор: идентификаторСобытия,
            порядок: порядок
        )
        switch try состояние.принять(событие, на: состояние.снимок, текст: текст, выделение: выделениеUTF16) {
        case .изменено: return .изменено
        case .безИзменений: return .безИзменений
        }
    }

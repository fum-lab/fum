/// Устраняет повторную обработку только того же живого объекта нативного события.
@MainActor
public final class ДедупликаторЭкземпляровНативныхСобытий {
    private let события = NSHashTable<AnyObject>(options: [.weakMemory, .objectPointerPersonality])

    public init() {}

    public func принять(_ событие: AnyObject) -> Bool {
        guard !события.contains(событие) else { return false }
        события.add(событие)
        return true
    }
}


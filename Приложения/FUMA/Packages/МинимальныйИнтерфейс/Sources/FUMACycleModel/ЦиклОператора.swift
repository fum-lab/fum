/// Общее runtime-состояние: геометрия меняет раскладку, но не исполнение и его историю.
public struct СостояниеЦиклаФУМА: Equatable, Sendable {
    public private(set) var версия: UInt64 = 0
    public private(set) var область: НаблюдениеКонтентнойОбласти?
    public private(set) var раскладка: РаскладкаИнтерфейсаФУМА?
    public private(set) var принятоНаблюденийГеометрии = 0
    public private(set) var отклоненоНаблюденийГеометрии = 0
    public private(set) var последняяОшибкаГеометрии: ОшибкаГеометрии?
    public private(set) var числоДействийПользователя = 0
    public private(set) var числоВызововИсполнителя = 0
    public private(set) var последнийРезультат: РезультатОдногоШага?
    public private(set) var последняяОшибкаИсполнения: String?
    public private(set) var история: [ЗаписьИсторииЦикла] = []
    public private(set) var рамкаОкна: НаблюдениеРамкиОкна?
    public private(set) var принятоНаблюденийРамки = 0
    public private(set) var отклоненоНаблюденийРамки = 0
    public private(set) var последняяОшибкаРамки: ОшибкаРамкиОкна?
    public private(set) var историяКлавиатуры: [ЗаписьВводаКлавиатуры] = []
    public private(set) var последняяОшибкаКлавиатуры: String?
    private var последнийНомерНаблюдения = 0
    private var последнийНомерРамки = 0
    private var последнийМоментРамкиНс: UInt64?

    public init() {}

    /// Применяет только снимок, созданный после уже показанного состояния.
    public mutating func применитьЕслиНовее(_ снимок: Self) {
        guard снимок.версия > версия else { return }
        self = снимок
    }

    mutating func принятьГеометрию(_ наблюдение: НаблюдениеКонтентнойОбласти) {
        версия += 1
        guard наблюдение.номер > последнийНомерНаблюдения else {
            отклонитьГеометрию(.устаревшийПорядок)
            return
        }
        последнийНомерНаблюдения = наблюдение.номер

        guard наблюдение.ширина.isFinite, наблюдение.высота.isFinite else {
            отклонитьГеометрию(.неКонечныйРазмер)
            return
        }
        guard наблюдение.ширина > 0, наблюдение.высота > 0 else {
            отклонитьГеометрию(.неположительныйРазмер)
            return
        }
        guard наблюдение.ширина <= 16_384, наблюдение.высота <= 16_384 else {
            отклонитьГеометрию(.размерЗаПределом)
            return
        }
        let ожидаемоеСобытие: СобытиеНаблюденияРазмеров = область == nil
            ? .первоначальноеНаблюдение
            : .изменениеРазмера
        guard наблюдение.событие == ожидаемоеСобытие else {
            отклонитьГеометрию(.неожиданноеСобытие)
            return
        }

        область = наблюдение
        раскладка = РаскладкаИнтерфейсаФУМА(ширина: наблюдение.ширина, высота: наблюдение.высота)
        принятоНаблюденийГеометрии += 1
        последняяОшибкаГеометрии = nil
    }

    mutating func принятьРамкуОкна(_ наблюдение: НаблюдениеРамкиОкна) {
        версия += 1
        guard наблюдение.номер > последнийНомерРамки else {
            отклонитьРамку(.устаревшийПорядок)
            return
        }
        последнийНомерРамки = наблюдение.номер

        guard наблюдение.x.isFinite, наблюдение.y.isFinite,
              наблюдение.ширина.isFinite, наблюдение.высота.isFinite else {
            отклонитьРамку(.неКонечнаяКоординатаИлиРазмер)
            return
        }
        guard наблюдение.ширина > 0, наблюдение.высота > 0 else {
            отклонитьРамку(.неположительныйРазмер)
            return
        }
        guard abs(наблюдение.x) <= 1_000_000, abs(наблюдение.y) <= 1_000_000,
              наблюдение.ширина <= 16_384, наблюдение.высота <= 16_384 else {
            отклонитьРамку(.размерЗаПределом)
            return
        }
        guard последнийМоментРамкиНс.map({ наблюдение.моментНаблюденияНс >= $0 }) ?? true else {
            отклонитьРамку(.времяУменьшилось)
            return
        }
        let ожидаемоеСобытие: СобытиеНаблюденияРамки?
        if let прежняяРамка = рамкаОкна {
            let перемещено = наблюдение.x != прежняяРамка.x || наблюдение.y != прежняяРамка.y
            let изменёнРазмер = наблюдение.ширина != прежняяРамка.ширина
                || наблюдение.высота != прежняяРамка.высота
            switch (перемещено, изменёнРазмер) {
            case (true, true): ожидаемоеСобытие = .изменениеПоложенияИРазмера
            case (true, false): ожидаемоеСобытие = .изменениеПоложения
            case (false, true): ожидаемоеСобытие = .изменениеРазмера
            case (false, false): ожидаемоеСобытие = nil
            }
        } else {
            ожидаемоеСобытие = .первоначальноеНаблюдение
        }
        guard let ожидаемоеСобытие, наблюдение.событие == ожидаемоеСобытие else {
            отклонитьРамку(.неожиданноеСобытие)
            return
        }
        рамкаОкна = наблюдение
        последнийМоментРамкиНс = наблюдение.моментНаблюденияНс
        принятоНаблюденийРамки += 1
        последняяОшибкаРамки = nil
    }

    mutating func записатьВводКлавиатуры(
        _ событие: ФизическоеСобытиеКлавиатуры,
        _ результат: РезультатВводаКлавиатурыОкна
    ) {
        версия += 1
        guard результат.статус != .повторСобытия else { return }
        if результат.трасса != nil { числоВызововИсполнителя += 1 }
        последняяОшибкаКлавиатуры = nil
        let исход: String
        switch результат.статус {
        case .обработано: исход = "Обработано"
        case .проигнорировано: исход = "Проигнорировано"
        case .повторСобытия: исход = "Повтор подавлен"
        case .раскладкаНеПроверена: исход = "Раскладка не проверена"
        case .неизвестно: исход = "Порядок или получатель неизвестен"
        }
        историяКлавиатуры.insert(ЗаписьВводаКлавиатуры(
            id: событие.идентификатор.rawValue,
            кодКлавиши: событие.код,
            фаза: событие.фаза,
            раскладка: событие.раскладка,
            порядок: событие.свидетельство.порядок,
            моментНаблюденияНс: событие.свидетельство.моментНаблюденияНс,
            статус: результат.статус,
            вывод: результат.вывод,
            исход: исход
        ), at: 0)
        if историяКлавиатуры.count > 100 { историяКлавиатуры.removeLast() }
    }

    mutating func записатьОшибкуКлавиатуры(_ ошибка: Error) {
        версия += 1
        let описание = (ошибка as? LocalizedError)?.errorDescription ?? String(reflecting: ошибка)
        последняяОшибкаКлавиатуры = описание
    }

    mutating func записатьОшибкуКлавиатуры(_ описание: String) {
        версия += 1
        последняяОшибкаКлавиатуры = описание
    }

    mutating func начатьДействие(вход: String, определение: String) -> Int {
        версия += 1
        числоДействийПользователя += 1
        let номер = числоДействийПользователя
        история.insert(ЗаписьИсторииЦикла(
            id: номер, вход: вход, определение: определение, исход: "Предложено; исполнение не завершено"
        ), at: 0)
        if история.count > 20 { история.removeLast() }
        последняяОшибкаИсполнения = nil
        return номер
    }

    mutating func зарегистрироватьВызовИсполнителя() {
        версия += 1
        числоВызововИсполнителя += 1
    }

    mutating func завершитьДействие(_ номер: Int, результат: РезультатОдногоШага) {
        версия += 1
        последнийРезультат = результат
        последняяОшибкаИсполнения = nil
        обновитьИсторию(номер, исход: "Выполнено: \(результат.текст)")
    }

    mutating func отказатьДействию(_ номер: Int, ошибка: Error) {
        версия += 1
        let описание = ошибка.localizedDescription
        последняяОшибкаИсполнения = описание
        обновитьИсторию(номер, исход: "Ошибка: \(описание)")
    }

    private mutating func отклонитьГеометрию(_ ошибка: ОшибкаГеометрии) {
        отклоненоНаблюденийГеометрии += 1
        последняяОшибкаГеометрии = ошибка
    }

    private mutating func отклонитьРамку(_ ошибка: ОшибкаРамкиОкна) {
        отклоненоНаблюденийРамки += 1
        последняяОшибкаРамки = ошибка
    }

    private mutating func обновитьИсторию(_ номер: Int, исход: String) {
        guard let индекс = история.firstIndex(where: { $0.id == номер }) else { return }
        let прежняя = история[индекс]
        история[индекс] = ЗаписьИсторииЦикла(
            id: прежняя.id, вход: прежняя.вход, определение: прежняя.определение, исход: исход
        )
    }
}

/// One MainActor-owned adapter provides synchronous native-key completion for the text view.
@MainActor
public final class ВладелецКлавиатурногоАдаптера {
    private var адаптер: АдаптерВводаОкна?
    private var окно: ИдентификаторОкнаВвода
    private var фокус: ИдентификаторФокусаВвода?
    private var поколениеФокуса: UInt64 = 0
    private var порядокСобытий: UInt64 = 0
    private var активна = false
    private var ошибкаИнициализацииАдаптера = false

    public init(окно: ИдентификаторОкнаВвода = ИдентификаторОкнаВвода(rawValue: UUID())) {
        self.окно = окно
    }

    public func выбратьОкно(_ новоеОкно: ИдентификаторОкнаВвода) {
        guard новоеОкно != окно else { return }
        деактивировать()
        окно = новоеОкно
        адаптер = nil
        поколениеФокуса = 0
        ошибкаИнициализацииАдаптера = false
    }

    public func деактивировать() {
        if let фокус { адаптер?.потерятьФокус(вОкне: окно, фокус: фокус) }
        фокус = nil
        активна = false
        порядокСобытий = 0
    }

    public func обработатьПростуюКлавишу(
        код: Int64,
        символСобытия: String?,
        повтор: Bool,
        моментНаблюденияНс: UInt64,
        идентификаторИсточника: String?,
        естьРазмеченнаяКомпозиция: Bool,
        модификаторы: ФлагиМодификаторовТекстовогоВвода
    ) throws -> СобытиеСРезультатомКлавиатуры? {
        guard !ошибкаИнициализацииАдаптера else { return nil }
        guard ПолитикаИсточникаВводаФУМА.разрешитьПростуюКлавишу(
            вид: .нажатие,
            код: код,
            символСобытия: символСобытия,
            модификаторы: модификаторы,
            идентификаторИсточника: идентификаторИсточника,
            естьРазмеченнаяКомпозиция: естьРазмеченнаяКомпозиция
        ) else {
            деактивировать()
            return nil
        }

        if !активна {
            guard поколениеФокуса < UInt64.max else { return nil }
            поколениеФокуса += 1
            let новыйФокус = ИдентификаторФокусаВвода(rawValue: UUID())
            do {
                try обеспечитьАдаптер(для: окно)
            } catch {
                ошибкаИнициализацииАдаптера = true
                деактивировать()
                throw ОшибкаВводаКлавиатуры.адаптерНеИнициализирован(
                    (error as? LocalizedError)?.errorDescription ?? String(reflecting: error)
                )
            }
            guard адаптер?.подтвердитьФокус(
                вОкне: окно,
                фокус: новыйФокус,
                поколение: поколениеФокуса,
                снимокМодификаторов: .пустое,
                моментНаблюденияНс: моментНаблюденияНс
            ) == true else { return nil }
            фокус = новыйФокус
            порядокСобытий = 0
            активна = true
        }

        let следующийПорядок = порядокСобытий.addingReportingOverflow(1)
        guard !следующийПорядок.overflow, let фокус else {
            деактивировать()
            return nil
        }
        порядокСобытий = следующийПорядок.partialValue
        let событие = ФизическоеСобытиеКлавиатуры(
            идентификатор: ИдентификаторСобытияКлавиатуры(rawValue: UUID()),
            свидетельство: СвидетельствоСобытияКлавиатуры(
                окно: окно,
                фокус: фокус,
                поколениеФокуса: поколениеФокуса,
                порядок: порядокСобытий,
                моментНаблюденияНс: моментНаблюденияНс
            ),
            код: код,
            фаза: .нажатие,
            повтор: повтор,
            раскладка: .qwerty,
            обработкаНативнымКраем: .fuma
        )
        do {
            let результат = try принять(событие)
            if результатТребуетСброса(результат) { деактивировать() }
            return СобытиеСРезультатомКлавиатуры(событие: событие, результат: результат)
        } catch {
            деактивировать()
            throw ОшибкаВводаКлавиатуры.исходИсполненияНеизвестен(
                (error as? LocalizedError)?.errorDescription ?? String(reflecting: error)
            )
        }
    }

    public func подтвердитьФокус(
        окно новоеОкно: ИдентификаторОкнаВвода,
        фокус новыйФокус: ИдентификаторФокусаВвода,
        поколение: UInt64,
        снимокМодификаторов: СостояниеМодификаторовКлавиатуры,
        моментНаблюденияНс: UInt64
    ) throws -> Bool {
        выбратьОкно(новоеОкно)
        try обеспечитьАдаптер(для: новоеОкно)
        let подтверждён = адаптер?.подтвердитьФокус(
            вОкне: новоеОкно,
            фокус: новыйФокус,
            поколение: поколение,
            снимокМодификаторов: снимокМодификаторов,
            моментНаблюденияНс: моментНаблюденияНс
        ) ?? false
        if подтверждён {
            окно = новоеОкно
            фокус = новыйФокус
            поколениеФокуса = max(поколениеФокуса, поколение)
            порядокСобытий = 0
            активна = true
        }
        return подтверждён
    }

    public func обработатьКлавиатурноеСобытие(
        _ событие: ФизическоеСобытиеКлавиатуры
    ) throws -> РезультатВводаКлавиатурыОкна {
        выбратьОкно(событие.свидетельство.окно)
        try обеспечитьАдаптер(для: событие.свидетельство.окно)
        let результат = try принять(событие)
        if результатТребуетСброса(результат) { деактивировать() }
        return результат
    }

    private func принять(
        _ событие: ФизическоеСобытиеКлавиатуры
    ) throws -> РезультатВводаКлавиатурыОкна {
        guard var адаптер else { throw ОшибкаОдногоШага.нетРесурсовАдаптераКлавиатуры }
        let результат = try адаптер.принять(событие)
        self.адаптер = адаптер
        return результат
    }

    private func обеспечитьАдаптер(для окно: ИдентификаторОкнаВвода) throws {
        if адаптер?.окно == окно { return }
        guard let definitionURL = Bundle.module.url(
            forResource: "определение-klaviatura", withExtension: "json"
        ), let tableURL = Bundle.module.url(forResource: "таблица-qwerty", withExtension: "json") else {
            throw ОшибкаОдногоШага.нетРесурсовАдаптераКлавиатуры
        }
        адаптер = try АдаптерВводаОкна(
            окно: окно,
            байтыОпределения: Data(contentsOf: definitionURL),
            байтыТаблицы: Data(contentsOf: tableURL),
            привязка: АдаптерВводаОкна.привязкаQwertyV1
        )
    }

    private func результатТребуетСброса(_ результат: РезультатВводаКлавиатурыОкна) -> Bool {
        результат.статус == .неизвестно || результат.статус == .раскладкаНеПроверена
    }
}

/// Последовательно вызывает существующий интерпретатор для одного простого текстового шага.
public actor ЦиклОператора {
    private struct ЗаголовокОпределения: Decodable {
        let схема: String
        let шаги: [ПустойШаг]

        struct ПустойШаг: Decodable {
            init(from decoder: Decoder) throws {}
        }
    }

    public init() {}

    public func наблюдатьРамкуОкна(_ наблюдение: НаблюдениеРамкиОкна) -> СостояниеЦиклаФУМА {
        состояние.принятьРамкуОкна(наблюдение)
        return состояние
    }

    public func снимок() -> СостояниеЦиклаФУМА { состояние }

    public func записатьРезультатКлавиатуры(
        _ наблюдение: СобытиеСРезультатомКлавиатуры
    ) -> СостояниеЦиклаФУМА {
        состояние.записатьВводКлавиатуры(наблюдение.событие, наблюдение.результат)
        return состояние
    }

    public func записатьОшибкуКлавиатуры(_ описание: String) -> СостояниеЦиклаФУМА {
        состояние.записатьОшибкуКлавиатуры(описание)
        return состояние
    }

    public func наблюдатьКонтентнуюОбласть(
        _ наблюдение: НаблюдениеКонтентнойОбласти
    ) -> СостояниеЦиклаФУМА {
        состояние.принятьГеометрию(наблюдение)
        return состояние
    }

    public func выполнитьОдинШаг(вход: String, определение: String) throws -> РезультатОдногоШага {
        let номерДействия = состояние.начатьДействие(вход: вход, определение: определение)
        do {
            let результат = try выполнитьОдинШагВоВнутреннемЦикле(вход: вход, определение: определение)
            состояние.завершитьДействие(номерДействия, результат: результат)
            return результат
        } catch {
            состояние.отказатьДействию(номерДействия, ошибка: error)
            throw error
        }
    }

    private func выполнитьОдинШагВоВнутреннемЦикле(
        вход: String, определение: String
    ) throws -> РезультатОдногоШага {
        guard вход.utf8.count <= 4096 else { throw ОшибкаОдногоШага.пределВхода }
        let байтыОпределения = Data(определение.utf8)
        guard байтыОпределения.count <= 16_384 else { throw ОшибкаОдногоШага.пределОпределения }

        let заголовок = try JSONDecoder().decode(ЗаголовокОпределения.self, from: байтыОпределения)
        guard заголовок.схема == "fum.определение-оператора.1" else {
            throw ОшибкаОдногоШага.неподдержаннаяСхема
        }
        guard заголовок.шаги.count == 1 else {
            throw ОшибкаОдногоШага.числоШагов(заголовок.шаги.count)
        }

        let программа = try ОпределениеОператора.разобрать(байтыОпределения)
        guard let шаг = программа.шаги.first else {
            throw ОшибкаОдногоШага.числоШагов(программа.шаги.count)
        }
        switch шаг.действие {
        case .обрезать, .нижнийРегистр, .сжатьПробелы, .заменить, .префикс:
            break
        default:
            throw ОшибкаОдногоШага.составнойОператор
        }

        состояние.зарегистрироватьВызовИсполнителя()
        let наблюдение = try AutomationExecutor.выполнить(
            программа,
            вход: .текст(вход),
            пределы: ПределыОдногоШага.значение
        )
        guard case .текст(let текст) = наблюдение.результат else {
            throw ОшибкаОдногоШага.нетекстовыйРезультат
        }
        return РезультатОдногоШага(
            текст: текст,
            хэшНаблюдения: наблюдение.хэшНаблюдения,
            выполненоОпераций: наблюдение.выполненоОпераций
        )
    }

    private var состояние = СостояниеЦиклаФУМА()
}

private enum ПределыОдногоШага {
    static let значение = ПределыИсполнения(
        байтовВхода: 4096,
        байтовРезультата: 16_384,
        операций: 65_536,
        записейТрассы: 16
    )
}

    public let исход: String
}

/// Общее runtime-состояние: геометрия меняет раскладку, но не исполнение и его историю.
public struct СостояниеЦиклаФУМА: Equatable, Sendable {
    public private(set) var версия: UInt64 = 0
    public private(set) var область: НаблюдениеКонтентнойОбласти?
    public private(set) var раскладка: РаскладкаИнтерфейсаФУМА?
    public private(set) var принятоНаблюденийГеометрии = 0
    public private(set) var отклоненоНаблюденийГеометрии = 0
    public private(set) var последняяОшибкаГеометрии: ОшибкаГеометрии?
    public private(set) var числоДействийПользователя = 0
    public private(set) var числоВызововИсполнителя = 0
    public private(set) var последнийРезультат: РезультатОдногоШага?
    public private(set) var последняяОшибкаИсполнения: String?
    public private(set) var история: [ЗаписьИсторииЦикла] = []
    private var последнийНомерНаблюдения = 0

    public init() {}

    /// Применяет только снимок, созданный после уже показанного состояния.
    public mutating func применитьЕслиНовее(_ снимок: Self) {
        guard снимок.версия > версия else { return }
        self = снимок
    }

    mutating func принятьГеометрию(_ наблюдение: НаблюдениеКонтентнойОбласти) {
        версия += 1
        guard наблюдение.номер > последнийНомерНаблюдения else {
            отклонитьГеометрию(.устаревшийПорядок)
            return
        }
        последнийНомерНаблюдения = наблюдение.номер

        guard наблюдение.ширина.isFinite, наблюдение.высота.isFinite else {
            отклонитьГеометрию(.неКонечныйРазмер)
            return
        }
        guard наблюдение.ширина > 0, наблюдение.высота > 0 else {
            отклонитьГеометрию(.неположительныйРазмер)
            return
        }
        guard наблюдение.ширина <= 16_384, наблюдение.высота <= 16_384 else {
            отклонитьГеометрию(.размерЗаПределом)
            return
        }
        let ожидаемоеСобытие: СобытиеНаблюденияРазмеров = область == nil
            ? .первоначальноеНаблюдение
            : .изменениеРазмера
        guard наблюдение.событие == ожидаемоеСобытие else {
            отклонитьГеометрию(.неожиданноеСобытие)
            return
        }

        область = наблюдение
        раскладка = РаскладкаИнтерфейсаФУМА(ширина: наблюдение.ширина, высота: наблюдение.высота)
        принятоНаблюденийГеометрии += 1
        последняяОшибкаГеометрии = nil
    }

    mutating func начатьДействие(вход: String, определение: String) -> Int {
        версия += 1
        числоДействийПользователя += 1
        let номер = числоДействийПользователя
        история.insert(ЗаписьИсторииЦикла(
            id: номер, вход: вход, определение: определение, исход: "Предложено; исполнение не завершено"
        ), at: 0)
        if история.count > 20 { история.removeLast() }
        последняяОшибкаИсполнения = nil
        return номер
    }

    mutating func зарегистрироватьВызовИсполнителя() {
        версия += 1
        числоВызововИсполнителя += 1
    }

    mutating func завершитьДействие(_ номер: Int, результат: РезультатОдногоШага) {
        версия += 1
        последнийРезультат = результат
        последняяОшибкаИсполнения = nil
        обновитьИсторию(номер, исход: "Выполнено: \(результат.текст)")
    }

    mutating func отказатьДействию(_ номер: Int, ошибка: Error) {
        версия += 1
        let описание = ошибка.localizedDescription
        последняяОшибкаИсполнения = описание
        обновитьИсторию(номер, исход: "Ошибка: \(описание)")
    }

    private mutating func отклонитьГеометрию(_ ошибка: ОшибкаГеометрии) {
        отклоненоНаблюденийГеометрии += 1
        последняяОшибкаГеометрии = ошибка
    }

    private mutating func обновитьИсторию(_ номер: Int, исход: String) {
        guard let индекс = история.firstIndex(where: { $0.id == номер }) else { return }
        let прежняя = история[индекс]
        история[индекс] = ЗаписьИсторииЦикла(
            id: прежняя.id, вход: прежняя.вход, определение: прежняя.определение, исход: исход
        )
    }
}

/// Последовательно вызывает существующий интерпретатор для одного простого текстового шага.
public actor ЦиклОператора {
    private struct ЗаголовокОпределения: Decodable {
        let схема: String
        let шаги: [ПустойШаг]

        struct ПустойШаг: Decodable {
            init(from decoder: Decoder) throws {}
        }
    }

    public init() {}

    public func снимок() -> СостояниеЦиклаФУМА { состояние }

    public func наблюдатьКонтентнуюОбласть(
        _ наблюдение: НаблюдениеКонтентнойОбласти
    ) -> СостояниеЦиклаФУМА {
        состояние.принятьГеометрию(наблюдение)
        return состояние
    }

    public func выполнитьОдинШаг(вход: String, определение: String) throws -> РезультатОдногоШага {
        let номерДействия = состояние.начатьДействие(вход: вход, определение: определение)
        do {
            let результат = try выполнитьОдинШагВоВнутреннемЦикле(вход: вход, определение: определение)
            состояние.завершитьДействие(номерДействия, результат: результат)
            return результат
        } catch {
            состояние.отказатьДействию(номерДействия, ошибка: error)
            throw error
        }
    }

    private func выполнитьОдинШагВоВнутреннемЦикле(
        вход: String, определение: String
    ) throws -> РезультатОдногоШага {
        guard вход.utf8.count <= 4096 else { throw ОшибкаОдногоШага.пределВхода }
        let байтыОпределения = Data(определение.utf8)
        guard байтыОпределения.count <= 16_384 else { throw ОшибкаОдногоШага.пределОпределения }

        let заголовок = try JSONDecoder().decode(ЗаголовокОпределения.self, from: байтыОпределения)
        guard заголовок.схема == "fum.определение-оператора.1" else {
            throw ОшибкаОдногоШага.неподдержаннаяСхема
        }
        guard заголовок.шаги.count == 1 else {
            throw ОшибкаОдногоШага.числоШагов(заголовок.шаги.count)
        }

        let программа = try ОпределениеОператора.разобрать(байтыОпределения)
        guard let шаг = программа.шаги.first else {
            throw ОшибкаОдногоШага.числоШагов(программа.шаги.count)
        }
        switch шаг.действие {
        case .обрезать, .нижнийРегистр, .сжатьПробелы, .заменить, .префикс:
            break
        default:
            throw ОшибкаОдногоШага.составнойОператор
        }

        состояние.зарегистрироватьВызовИсполнителя()
        let наблюдение = try AutomationExecutor.выполнить(
            программа,
            вход: .текст(вход),
            пределы: ПределыОдногоШага.значение
        )
        guard case .текст(let текст) = наблюдение.результат else {
            throw ОшибкаОдногоШага.нетекстовыйРезультат
        }
        return РезультатОдногоШага(
            текст: текст,
            хэшНаблюдения: наблюдение.хэшНаблюдения,
            выполненоОпераций: наблюдение.выполненоОпераций
        )
    }

    private var состояние = СостояниеЦиклаФУМА()
}

private enum ПределыОдногоШага {
    static let значение = ПределыИсполнения(
        байтовВхода: 4096,
        байтовРезультата: 16_384,
        операции: 65_536,
        записейТрассы: 16
    )
}

public enum РешениеВводаКлавиатуры: Equatable, Sendable {
    case применитьFUMA
    case передатьНативно
    case подавитьПовтор
    case безЭффектаНеизвестно

    public static func классифицировать(_ результат: РезультатВводаКлавиатурыОкна) -> Self {
        if результат.статус == .неизвестно || результат.маршрут == .неизвестен {
            return .безЭффектаНеизвестно
        }
        if результат.статус == .повторСобытия || результат.маршрут == .подавитьПовтор {
            return .подавитьПовтор
        }
        switch результат.маршрут {
        case .потребить: return .применитьFUMA
        case .пропустить: return .передатьНативно
        case .подавитьПовтор: return .подавитьПовтор
        case .неизвестен: return .безЭффектаНеизвестно
        }
    }
}


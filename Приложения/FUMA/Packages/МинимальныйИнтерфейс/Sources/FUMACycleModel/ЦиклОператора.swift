public struct РезультатОдногоШага: Equatable, Sendable {
    public let текст: String
    public let хэшНаблюдения: String
    public let выполненоОпераций: Int

    public init(текст: String, хэшНаблюдения: String, выполненоОпераций: Int) {
        self.текст = текст
        self.хэшНаблюдения = хэшНаблюдения
        self.выполненоОпераций = выполненоОпераций
    }
}

public enum ОшибкаОдногоШага: Error, Equatable, LocalizedError, Sendable {
    case пределВхода
    case пределОпределения
    case неподдержаннаяСхема
    case числоШагов(Int)
    case составнойОператор
    case нетекстовыйРезультат

    public var errorDescription: String? {
        switch self {
        case .пределВхода:
            return "Вход превышает предел 4096 байтов UTF-8."
        case .пределОпределения:
            return "Определение превышает предел 16384 байта."
        case .неподдержаннаяСхема:
            return "Разрешена только схема fum.определение-оператора.1."
        case .числоШагов(let число):
            return "Ожидался ровно один шаг; получено: \(число)."
        case .составнойОператор:
            return "Допускаются только простые текстовые операторы одного шага."
        case .нетекстовыйРезультат:
            return "Для этого окна поддерживается только текстовый результат."
        }
    }
}


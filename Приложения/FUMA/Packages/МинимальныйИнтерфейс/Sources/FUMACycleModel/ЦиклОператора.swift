public struct РезультатРедактированияКлавиатуры: Equatable, Sendable {
    public let текст: String
    public let выделениеUTF16: Range<Int>
    public let заменяемыйДиапазонUTF16: Range<Int>
    public let вставка: String
}

public enum РедакторТекстаКлавиатуры {
    public static func вставить(
        _ вставка: String,
        в исходныйТекст: String,
        выделениеUTF16: Range<Int>
    ) -> РезультатРедактированияКлавиатуры? {
        let source = исходныйТекст as NSString
        guard диапазонДопустим(выделениеUTF16, длина: source.length) else { return nil }
        let updated = source.replacingCharacters(
            in: NSRange(location: выделениеUTF16.lowerBound, length: выделениеUTF16.count),
            with: вставка
        )
        let caret = выделениеUTF16.lowerBound + (вставка as NSString).length
        return РезультатРедактированияКлавиатуры(
            текст: updated,
            выделениеUTF16: caret..<caret,
            заменяемыйДиапазонUTF16: выделениеUTF16,
            вставка: вставка
        )
    }

    public static func удалитьНазад(
        из исходногоТекста: String,
        выделениеUTF16: Range<Int>
    ) -> РезультатРедактированияКлавиатуры? {
        let source = исходногоТекста as NSString
        guard диапазонДопустим(выделениеUTF16, длина: source.length) else { return nil }
        let удаляемыйДиапазон: NSRange
        if !выделениеUTF16.isEmpty {
            удаляемыйДиапазон = NSRange(
                location: выделениеUTF16.lowerBound,
                length: выделениеUTF16.count
            )
        } else if выделениеUTF16.lowerBound > 0 {
            удаляемыйДиапазон = source.rangeOfComposedCharacterSequence(
                at: выделениеUTF16.lowerBound - 1
            )
        } else {
            return РезультатРедактированияКлавиатуры(
                текст: исходногоТекста,
                выделениеUTF16: выделениеUTF16,
                заменяемыйДиапазонUTF16: выделениеUTF16,
                вставка: ""
            )
        }
        let updated = source.replacingCharacters(in: удаляемыйДиапазон, with: "")
        let caret = удаляемыйДиапазон.location
        let нижняяГраница = удаляемыйДиапазон.location
        let верхняяГраница = нижняяГраница + удаляемыйДиапазон.length
        return РезультатРедактированияКлавиатуры(
            текст: updated,
            выделениеUTF16: caret..<caret,
            заменяемыйДиапазонUTF16: нижняяГраница..<верхняяГраница,
            вставка: ""
        )
    }

    private static func диапазонДопустим(_ диапазон: Range<Int>, длина: Int) -> Bool {
        диапазон.lowerBound >= 0 && диапазон.upperBound >= диапазон.lowerBound
            && диапазон.upperBound <= длина
    }
}


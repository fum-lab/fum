import Foundation
import XCTest
@testable import СнимокАгентскойЗадачи

func изменить(_ вход: Наблюдение, источник: Источник? = nil, область: String? = nil,
              задача: Задача? = nil, версия: Int? = nil, факт: Факт? = nil,
              исходныйФакт: String? = nil) -> Наблюдение {
    Наблюдение(версия: версия ?? вход.версия, идентификатор: вход.идентификатор,
        задача: задача ?? вход.задача, источник: источник ?? вход.источник,
        такт: вход.такт, годноДо: вход.годноДо, охват: вход.охват,
        область: область ?? вход.область, исходныйФакт: исходныйФакт ?? вход.исходныйФакт,
        заменяет: вход.заменяет, факт: факт ?? вход.факт)
}

final class ГраницыTests: XCTestCase {
    func testПатологическиеКаноническиРавныеИдентификаторыОбаОтклоняются() throws {
        let первая = String(repeating: String(UnicodeScalar(0x0344)!), count: 32)
        let вторая = String(repeating: String(UnicodeScalar(0x0308)!) + String(UnicodeScalar(0x0301)!), count: 32)
        XCTAssertEqual(первая, вторая)
        XCTAssertLessThanOrEqual(первая.utf8.count, 128)
        XCTAssertLessThanOrEqual(вторая.utf8.count, 128)
        for идентификатор in [первая, вторая] {
            let задача = Задача(поставщик: "стенд", хост: "стенд", идентификатор: идентификатор)
            XCTAssertThrowsError(try Редуктор(задача: задача))
        }
    }
    func testUnicodeБайтыСохраняютсяАХэшИдентичностиСнимкаНормализован() throws {
        let составная = Задача(поставщик: "синтетический", хост: "стенд", идентификатор: "мой")
        let разложенная = Задача(поставщик: "синтетический".decomposedStringWithCanonicalMapping,
            хост: "стенд", идентификатор: "мой".decomposedStringWithCanonicalMapping)
        XCTAssertEqual(составная, разложенная)
        XCTAssertNotEqual(try каноническийJSON(составная), try каноническийJSON(разложенная))
        XCTAssertEqual(try хэшСнимка(Редуктор(задача: составная).снимок),
                       try хэшСнимка(Редуктор(задача: разложенная).снимок))
    }
    func testТактНеЯвляетсяПричинойКорректировки() throws {
        var редуктор = try Редуктор(задача: задачаПримера)
        try редуктор.принять(запись(1, .время))
        XCTAssertThrowsError(try редуктор.принять(запись(2,
            .команда(операция: "оп", фаза: .отправлена, эффект: "исправлено", корректирует: "н-1"), канал: .команда)))
    }
    func testПолныйСписокВОбластиНеДоказываетГлобальноеОтсутствие() throws {
        let снимок = try свернуть([
            запись(1, .значение(поле: .существует, контекст: "", текст: "да")),
            изменить(запись(2, .список(задачи: []), канал: .api, охват: .полный), область: "только-активные")
        ])
        XCTAssertEqual(снимок.значение(.существует).кандидаты.map(\.значение), ["да"])
        XCTAssertEqual(снимок.разрывыОхвата, ["н-2"])
    }
    func testЧужаяОбластьЭффектаНеПодтверждаетКоманду() throws {
        var редуктор = try Редуктор(задача: задачаПримера)
        try редуктор.принять(запись(1, .команда(операция: "оп", фаза: .отправлена, эффект: "открыта", корректирует: nil), канал: .команда))
        let до = редуктор.снимок
        XCTAssertThrowsError(try редуктор.принять(изменить(
            запись(2, .эффект(операция: "оп", текст: "открыта"), канал: .интерфейс),
            область: "другая-вкладка")))
        XCTAssertEqual(редуктор.снимок, до)
    }
    func testПринятиеНеМеняетОбластьИсходнойОтправки() throws {
        var редуктор = try Редуктор(задача: задачаПримера)
        try редуктор.принять(запись(1, .команда(операция: "оп", фаза: .отправлена, эффект: "открыта", корректирует: nil), канал: .команда))
        XCTAssertThrowsError(try редуктор.принять(изменить(
            запись(2, .команда(операция: "оп", фаза: .принята, эффект: "открыта", корректирует: nil), канал: .команда),
            область: "другая-вкладка")))
    }
    func testНовыйЭкземплярНеОбходитОтказКанала() throws {
        let снимок = try свернуть([
            запись(1, .отказ(причина: "нет полномочий"), канал: .интерфейс),
            изменить(запись(2, .значение(поле: .текущаяРабота, контекст: "", текст: "невозможное"), канал: .интерфейс),
                источник: Источник(.интерфейс, "новый-экземпляр"))
        ])
        XCTAssertEqual(снимок.значение(.текущаяРабота).знание, .неизвестно)
        XCTAssertEqual(снимок.проигнорированы, ["н-2"])
    }
    func testКонфигурацияНеДоказываетМодельХода() throws {
        XCTAssertThrowsError(try свернуть([
            запись(1, .значение(поле: .наблюдённаяМодель, контекст: "ход-1", текст: "модель-А"), канал: .настройка)
        ]))
    }
    func testУстаревшийКонфликтСохраняетОбаСвидетельства() throws {
        let снимок = try свернуть([
            запись(1, .значение(поле: .текущаяРабота, контекст: "", текст: "А"), годноДо: 2),
            запись(2, .значение(поле: .текущаяРабота, контекст: "", текст: "Б"), канал: .api, годноДо: 2),
            запись(3, .время)
        ])
        XCTAssertEqual(снимок.значение(.текущаяРабота).знание, .противоречие)
        XCTAssertEqual(снимок.значение(.текущаяРабота).кандидаты.map(\.свидетельство), ["н-1", "н-2"])
        XCTAssertTrue(снимок.значение(.текущаяРабота).кандидаты.allSatisfy(\.устарело))
        XCTAssertEqual(снимок.значение(.ожидание).знание, .неизвестно)
    }
    func testЯвноеЗамещениеНеТеряетИсходникИНеРазрешаетЧужойКонфликт() throws {
        let снимок = try свернуть([
            запись(1, .значение(поле: .текущаяРабота, контекст: "", текст: "А")),
            запись(2, .значение(поле: .текущаяРабота, контекст: "", текст: "Б"), заменяет: ["н-1"])
        ])
        XCTAssertEqual(снимок.наблюдения.count, 2)
        XCTAssertEqual(снимок.значение(.текущаяРабота).кандидаты.map(\.значение), ["Б"])
        XCTAssertThrowsError(try свернуть([
            запись(1, .значение(поле: .текущаяРабота, контекст: "", текст: "А")),
            запись(2, .значение(поле: .текущаяРабота, контекст: "", текст: "Б"), канал: .api, заменяет: ["н-1"])
        ]))
    }
    func testПоследняяКорректировкаТолькоПослеЭффекта() throws {
        var редуктор = try Редуктор(задача: задачаПримера)
        let входы = [
            запись(1, .расхождение(ожидалось: "исправлено", наблюдалось: "ошибка"), канал: .интерфейс),
            запись(2, .команда(операция: "исправление-1", фаза: .отправлена, эффект: "исправлено", корректирует: "н-1"), канал: .команда),
            запись(3, .значение(поле: .ожидание, контекст: "", текст: "процесс"))
        ]
        for вход in входы { try редуктор.принять(вход) }
        XCTAssertNil(редуктор.снимок.последняяПодтверждённаяКорректировка)
        try редуктор.принять(запись(4, .эффект(операция: "исправление-1", текст: "исправлено"), канал: .интерфейс))
        XCTAssertEqual(редуктор.снимок.последняяПодтверждённаяКорректировка, "исправление-1")
        XCTAssertEqual(редуктор.снимок.операции.first?.подтверждение, "н-4")
        XCTAssertEqual(редуктор.снимок.значение(.ожидание).кандидаты.first?.значение, "процесс")
    }
    func testПовторНеОсвежаетВремяИНедетерминированностиНет() throws {
        let вход = запись(1, .значение(поле: .текущаяРабота, контекст: "", текст: "сборка"), годноДо: 1)
        let снимок = try свернуть([вход, запись(2, .время), вход])
        XCTAssertTrue(снимок.значение(.текущаяРабота).кандидаты[0].устарело)
        XCTAssertEqual(try каноническийJSON(снимок), try каноническийJSON(свернуть([вход, запись(2, .время)])))
    }
    func testНеполныйИНеоднозначныйJSONНеПринимается() throws {
        let сценарий = Сценарий(задача: задачаПримера, наблюдения: [запись(1, .время)])
        let данные = try каноническийJSON(сценарий)
        XCTAssertEqual(try прочитатьСценарий(данные), сценарий)
        XCTAssertThrowsError(try прочитатьСценарий(данные.dropLast()))
        let строка = String(decoding: данные, as: UTF8.self)
        XCTAssertThrowsError(try прочитатьСценарий(Data(строка.replacingOccurrences(of: "\"версия\":1", with: "\"версия\":1,\"версия\":1").utf8)))
        XCTAssertThrowsError(try прочитатьСценарий(Data(строка.replacingOccurrences(of: "{", with: "{\"неизвестное\":1,", range: строка.startIndex..<строка.index(after: строка.startIndex)).utf8)))
    }
    func testЧужаяИдентичностьВерсияИПределДоСменыСнимка() throws {
        var редуктор = try Редуктор(задача: задачаПримера)
        let вход = запись(1, .время)
        XCTAssertThrowsError(try редуктор.принять(изменить(вход, задача: Задача(поставщик: "чужой", хост: "стенд", идентификатор: "задача-1"))))
        XCTAssertThrowsError(try редуктор.принять(изменить(вход, версия: 2)))
        XCTAssertTrue(редуктор.снимок.наблюдения.isEmpty)
        for номер in 0..<256 {
            try редуктор.принять(Наблюдение(идентификатор: "т-\(номер)", задача: задачаПримера,
                источник: Источник(.журнал), такт: Int64(номер), годноДо: Int64(номер), факт: .время))
        }
        let до = редуктор.снимок
        XCTAssertThrowsError(try редуктор.принять(Наблюдение(идентификатор: "лишнее", задача: задачаПримера,
            источник: Источник(.журнал), такт: 256, годноДо: 256, факт: .время)))
        XCTAssertEqual(редуктор.снимок, до)
    }
}

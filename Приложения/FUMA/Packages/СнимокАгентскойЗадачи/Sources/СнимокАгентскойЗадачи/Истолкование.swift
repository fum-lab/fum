import Foundation

public enum БюджетСнимка {
    public static let наблюдения = 256
    public static let вход = 4 * 1024 * 1024
    public static let наблюдение = 16 * 1024
    public static let запись = 32 * 1024
}

func проверитьСтроку(_ строка: String, предел: Int = 1024, пустая: Bool = false) throws {
    guard (пустая || !строка.isEmpty), строка.utf8.count <= предел,
          !строка.unicodeScalars.contains(where: { $0.value < 32 || $0.value == 127 }) else {
        throw ОшибкаСнимка.неверныйВвод
    }
}
func проверитьЗадачу(_ задача: Задача) throws {
    for строка in [задача.поставщик, задача.хост, задача.идентификатор] {
        try проверитьСтроку(строка, предел: 128)
        let ключ = строка.precomposedStringWithCanonicalMapping
        try проверитьСтроку(ключ, предел: 128)
        // Машинная идентичность v1: буквы, десятичные цифры и . _ : - .
        // Остаточные combining marks и символы интерфейсных подписей не являются ID.
        guard ключ.unicodeScalars.allSatisfy({ символ in
            switch символ.properties.generalCategory {
            case .uppercaseLetter, .lowercaseLetter, .titlecaseLetter, .modifierLetter,
                 .otherLetter, .decimalNumber: return true
            default: return "._:-".unicodeScalars.contains(символ)
            }
        }) else { throw ОшибкаСнимка.неверныйВвод }
    }
}
func проверитьНаблюдение(_ наблюдение: Наблюдение) throws {
    guard наблюдение.версия == 1 else { throw ОшибкаСнимка.версия }
    guard наблюдение.заменяет.count <= 16 else { throw ОшибкаСнимка.предел }
    try проверитьЗадачу(наблюдение.задача)
    try проверитьСтроку(наблюдение.идентификатор, предел: 128)
    try проверитьСтроку(наблюдение.источник.экземпляр, предел: 128)
    try проверитьСтроку(наблюдение.область)
    try проверитьСтроку(наблюдение.исходныйФакт, предел: 8192)
    guard наблюдение.такт >= 0, наблюдение.годноДо >= наблюдение.такт,
          Set(наблюдение.заменяет).count == наблюдение.заменяет.count else {
        throw ОшибкаСнимка.неверныйВвод
    }
    for ссылка in наблюдение.заменяет { try проверитьСтроку(ссылка, предел: 128) }
    switch наблюдение.факт {
    case let .значение(поле, контекст, текст):
        let допустимые: [Канал]
        switch поле {
        case .наблюдённаяМодель: допустимые = [.журнал, .интерфейс]
        case .желаемаяМодель: допустимые = [.настройка, .интерфейс]
        case .каталогRuntime: допустимые = [.журнал]
        case .каталогКоманды: допустимые = [.команда]
        case .назначенныйWorktree: допустимые = [.настройка]
        case .ветка: допустимые = [.журнал, .команда]
        case .существует, .текущаяРабота, .ожидание: допустимые = [.журнал, .api, .интерфейс]
        }
        guard допустимые.contains(наблюдение.источник.канал) else { throw ОшибкаСнимка.неверныйВвод }
        try проверитьСтроку(контекст, предел: 128, пустая: true)
        try проверитьСтроку(текст)
        let сКонтекстом = [.наблюдённаяМодель, .каталогКоманды, .ветка].contains(поле)
        guard сКонтекстом == !контекст.isEmpty else { throw ОшибкаСнимка.неверныйВвод }
        if поле == .существует && !["да", "нет"].contains(текст) { throw ОшибкаСнимка.неверныйВвод }
        if поле == .ожидание && !["нет", "пользователь", "полномочия", "процесс", "другая-задача"].contains(текст) {
            throw ОшибкаСнимка.неверныйВвод
        }
    case let .список(задачи):
        guard наблюдение.источник.канал == .api, наблюдение.охват != .точечный,
              задачи.count <= 256, Set(задачи).count == задачи.count else { throw ОшибкаСнимка.неверныйВвод }
        for задача in задачи { try проверитьЗадачу(задача) }
    case let .отказ(причина): try проверитьСтроку(причина)
    case let .расхождение(ожидалось, наблюдалось):
        guard наблюдение.источник.канал == .интерфейс, ожидалось != наблюдалось else {
            throw ОшибкаСнимка.неверныйВвод
        }
        try проверитьСтроку(ожидалось)
        try проверитьСтроку(наблюдалось)
    case let .команда(операция, _, эффект, корректирует):
        guard наблюдение.источник.канал == .команда else { throw ОшибкаСнимка.неверныйВвод }
        try проверитьСтроку(операция, предел: 128)
        try проверитьСтроку(эффект)
        if let корректирует { try проверитьСтроку(корректирует, предел: 128) }
    case let .эффект(операция, текст):
        guard наблюдение.источник.канал == .интерфейс else { throw ОшибкаСнимка.неподтверждаемыйЭффект }
        try проверитьСтроку(операция, предел: 128)
        try проверитьСтроку(текст)
    case .время: break
    }
    if case .значение = наблюдение.факт {} else if !наблюдение.заменяет.isEmpty {
        throw ОшибкаСнимка.неверныйВвод
    }
    // Только после структурных лимитов: ограниченный промежуточный JSON.
    guard try каноническийJSON(наблюдение).count <= БюджетСнимка.наблюдение else { throw ОшибкаСнимка.предел }
}

// До Codable: ограничиваем память и глубину. Каноническая форма исключает
// повторные/неизвестные ключи и неоднозначные варианты строк/чисел.
func декодировать<Значение: Codable>(_ тип: Значение.Type, _ данные: Data, предел: Int) throws -> Значение {
    guard данные.count <= предел else { throw ОшибкаСнимка.предел }
    var глубина = 0
    var строка = false
    var экранировано = false
    for байт in данные {
        if строка {
            if экранировано { экранировано = false }
            else if байт == 92 { экранировано = true }
            else if байт == 34 { строка = false }
        } else {
            if байт == 34 { строка = true }
            if байт == 123 || байт == 91 {
                глубина += 1
                guard глубина <= 12 else { throw ОшибкаСнимка.предел }
            }
            if байт == 125 || байт == 93 { глубина -= 1 }
            guard глубина >= 0 else { throw ОшибкаСнимка.неверныйВвод }
        }
    }
    guard глубина == 0, !строка else { throw ОшибкаСнимка.неверныйВвод }
    let значение: Значение
    do { значение = try JSONDecoder().decode(тип, from: данные) }
    catch { throw ОшибкаСнимка.неверныйВвод }
    var сравниваемые = данные
    if сравниваемые.last == 10 { сравниваемые.removeLast() }
    guard try каноническийJSON(значение) == сравниваемые else { throw ОшибкаСнимка.неверныйВвод }
    return значение
}

public func проверитьСценарий(_ сценарий: Сценарий) throws {
    guard сценарий.версия == 1 else { throw ОшибкаСнимка.версия }
    try проверитьЗадачу(сценарий.задача)
    guard !сценарий.наблюдения.isEmpty, сценарий.наблюдения.count <= БюджетСнимка.наблюдения else {
        throw ОшибкаСнимка.предел
    }
    var редуктор = try Редуктор(задача: сценарий.задача)
    for наблюдение in сценарий.наблюдения { try редуктор.принять(наблюдение) }
}
public func прочитатьСценарий(_ данные: Data) throws -> Сценарий {
    let сценарий = try декодировать(Сценарий.self, данные, предел: БюджетСнимка.вход)
    try проверитьСценарий(сценарий)
    return сценарий
}

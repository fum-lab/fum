import Foundation
import Testing
import АрхивныйСнимокЗадачи

@Suite("Типизированная граница курсора JSONL")
struct ПроверкиГраницыКурсораJSONL {
    @Test("Завершённые LF-записи, абсолютные смещения и EOF-хвост образуют курсор")
    func завершённыеЗаписиИХвост() throws {
        let срез = try БайтовыйСрезJSONL(начало: 37, данные: Data([0x61, 0x0a, 0x0a, 0x62]))
        let исход = try сверитьРамкиJSONL(срез)

        guard case let .продолжение(записи, хвост, курсор) = исход else {
            Issue.record("Первичное чтение должно вернуть продолжение")
            return
        }
        #expect(записи.map(\.данные) == [Data([0x61, 0x0a]), Data([0x0a])])
        #expect(записи.map(\.позиция.номер) == [1, 2])
        #expect(записи.map(\.позиция.начало) == [37, 39])
        #expect(записи.map(\.позиция.конец) == [39, 40])
        #expect(хвост?.данные == Data([0x62]))
        #expect(хвост?.начало == 40)
        #expect(хвост?.конец == 41)
        #expect(курсор.началоСреза == 37)
        #expect(курсор.префикс.байты == 3)
        #expect(курсор.префикс.строки == 2)
        #expect(курсор.префикс.sha256
            == "a7da489976d0047490617adb4f7a1f27f7af8b52a5176fd002ffe471863520ab")
        #expect(курсор.следующееСмещение == 41)
        #expect(курсор.неполныйХвост == Data([0x62]))

        let сохранённый = try JSONEncoder().encode(курсор)
        #expect(try JSONDecoder().decode(КурсорРамокJSONL.self, from: сохранённый) == курсор)
    }

    @Test("Точный replay не выдаёт записи повторно, а дополнение завершает прежний хвост")
    func повторИПродолжение() throws {
        let первыйСрез = try БайтовыйСрезJSONL(начало: 100, данные: Data("a\npar".utf8))
        let первыйИсход = try сверитьРамкиJSONL(первыйСрез)
        guard case let .продолжение(_, _, первыйКурсор) = первыйИсход else {
            Issue.record("Первичное чтение должно вернуть курсор")
            return
        }

        #expect(try сверитьРамкиJSONL(первыйСрез, после: первыйКурсор)
            == .повтор(курсор: первыйКурсор))
        let узкиеПределы = try ПределыПоследовательныхРамок(
            порция: 4, строка: 4, рамки: 1, байты: 4)
        #expect(throws: ОшибкаАрхива.предел) {
            try сверитьРамкиJSONL(
                первыйСрез, после: первыйКурсор, пределы: узкиеПределы)
        }

        let дополненный = try БайтовыйСрезJSONL(начало: 100, данные: Data("a\npartial\nx".utf8))
        let следующийИсход = try сверитьРамкиJSONL(дополненный, после: первыйКурсор)
        guard case let .продолжение(записи, хвост, курсор) = следующийИсход else {
            Issue.record("Дополнение должно продвинуть курсор")
            return
        }
        #expect(записи.count == 1)
        #expect(записи.first?.данные == Data("partial\n".utf8))
        #expect(записи.first?.позиция.номер == 2)
        #expect(записи.first?.позиция.начало == 102)
        #expect(записи.first?.позиция.конец == 110)
        #expect(хвост?.данные == Data("x".utf8))
        #expect(хвост?.начало == 110)
        #expect(хвост?.конец == 111)
        #expect(курсор.префикс.байты == 10)
        #expect(курсор.префикс.строки == 2)
        #expect(курсор.префикс.sha256
            == "29611218b70f9a275b72bb4225c32fb41b240eb99a19af596832157516e36351")
        #expect(курсор.следующееСмещение == 111)
    }

    @Test("Дрейф завершённого префикса и прежнего EOF-хвоста различается")
    func дрейфПрефиксаИХвоста() throws {
        let исходный = try БайтовыйСрезJSONL(начало: 100, данные: Data("a\npart".utf8))
        let исход = try сверитьРамкиJSONL(исходный)
        guard case let .продолжение(_, _, курсор) = исход else {
            Issue.record("Первичное чтение должно вернуть курсор")
            return
        }

        let инойПрефикс = try БайтовыйСрезJSONL(начало: 100, данные: Data("A\npart".utf8))
        #expect(try сверитьРамкиJSONL(инойПрефикс, после: курсор)
            == .дрейф(.завершённыйПрефикс(провереноДо: 102)))

        let инойХвост = try БайтовыйСрезJSONL(начало: 100, данные: Data("a\npArt".utf8))
        #expect(try сверитьРамкиJSONL(инойХвост, после: курсор)
            == .дрейф(.неполныйХвост(начало: 102, конец: 106)))
    }

    @Test("Сверка прежних байтов опережает предел новой строки")
    func дрейфОпережаетПредел() throws {
        let исходный = try БайтовыйСрезJSONL(начало: 100, данные: Data("a\nx".utf8))
        let исход = try сверитьРамкиJSONL(исходный)
        guard case let .продолжение(_, _, курсор) = исход else {
            Issue.record("Первичное чтение должно вернуть курсор")
            return
        }
        let пределы = try ПределыПоследовательныхРамок(
            порция: 4, строка: 2, рамки: 2, байты: 8)

        let безПрежнегоLF = try БайтовыйСрезJSONL(
            начало: 100, данные: Data("abxq".utf8))
        #expect(try сверитьРамкиJSONL(безПрежнегоLF, после: курсор, пределы: пределы)
            == .дрейф(.завершённыйПрефикс(провереноДо: 102)))

        let инойХвост = try БайтовыйСрезJSONL(
            начало: 100, данные: Data("a\nyqq".utf8))
        #expect(try сверитьРамкиJSONL(инойХвост, после: курсор, пределы: пределы)
            == .дрейф(.неполныйХвост(начало: 102, конец: 103)))
    }

    @Test("Усечение и несовместимое начало среза не считаются replay")
    func усечениеИНачалоСреза() throws {
        let исходный = try БайтовыйСрезJSONL(начало: 100, данные: Data("a\npart".utf8))
        let исход = try сверитьРамкиJSONL(исходный)
        guard case let .продолжение(_, _, курсор) = исход else {
            Issue.record("Первичное чтение должно вернуть курсор")
            return
        }

        let усечённый = try БайтовыйСрезJSONL(начало: 100, данные: Data("a\npar".utf8))
        #expect(try сверитьРамкиJSONL(усечённый, после: курсор)
            == .дрейф(.усечение(ожидалосьДо: 106, полученоДо: 105)))

        let иноеНачало = try БайтовыйСрезJSONL(начало: 101, данные: Data("a\npart".utf8))
        #expect(try сверитьРамкиJSONL(иноеНачало, после: курсор)
            == .дрейф(.несовместимоеНачало(ожидалось: 100, получено: 101)))
    }
}

private func просканировать(_ данные: Data, начало: Int, размерПорции: Int) throws
    -> ([РамкаПотока], ИтогПоследовательныхРамок) {
    let пределы = try ПределыПоследовательныхРамок(порция: размерПорции, строка: 262_144,
        рамки: 128, байты: данные.count)
    let поток = try ПоследовательныеРамкиJSONL(начальноеСмещение: начало, пределы: пределы)
    var рамки: [РамкаПотока] = []
    var смещение = начало
    for место in stride(from: 0, to: данные.count, by: размерПорции) {
        let конец = min(место + размерПорции, данные.count)
        смещение = try поток.принять(Data(данные[место..<конец]), смещение: смещение) { рамки.append($0) }
    }
    return (рамки, try поток.завершить())
}

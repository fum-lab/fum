@Test func повторныйВходИзCallbackЗакрываетЭкземпляр() throws {
    let повтор = try ПоследовательныеРамкиJSONL()
    var выданныеПовтором: [Data] = []
    var вложенныйОтказ: ОшибкаПоследовательныхРамок?
    #expect(throws: ОшибкаПоследовательныхРамок.отказ) {
        try повтор.принять(Data("a\nb\nc\n".utf8), смещение: 0) { рамка in
            выданныеПовтором.append(рамка.данные)
            do { try повтор.принять(Data("z\n".utf8), смещение: 0) { _ in } }
            catch let ошибка as ОшибкаПоследовательныхРамок { вложенныйОтказ = ошибка }
        }
    }
    #expect(вложенныйОтказ == .повторныйВход)
    #expect(выданныеПовтором == [Data("a\n".utf8)])
    #expect(throws: ОшибкаПоследовательныхРамок.отказ) { try повтор.завершить() }

    let завершение = try ПоследовательныеРамкиJSONL()
    var выданныеЗавершением: [Data] = []
    вложенныйОтказ = nil
    #expect(throws: ОшибкаПоследовательныхРамок.отказ) {
        try завершение.принять(Data("a\nb\nc\n".utf8), смещение: 0) { рамка in
            выданныеЗавершением.append(рамка.данные)
            do { _ = try завершение.завершить() }
            catch let ошибка as ОшибкаПоследовательныхРамок { вложенныйОтказ = ошибка }
        }
    }
    #expect(вложенныйОтказ == .повторныйВход)
    #expect(выданныеЗавершением == [Data("a\n".utf8)])
    #expect(throws: ОшибкаПоследовательныхРамок.отказ) {
        try завершение.принять(Data(), смещение: 0) { _ in }
    }
    #expect(throws: ОшибкаПоследовательныхРамок.отказ) { try завершение.завершить() }
}


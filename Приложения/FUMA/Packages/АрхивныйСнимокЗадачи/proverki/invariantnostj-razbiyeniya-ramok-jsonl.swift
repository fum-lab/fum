import Foundation
import Testing
import АрхивныйСнимокЗадачи

@Suite("Инвариантность разбиения рамок JSONL")
struct ИнвариантностьРазбиенияРамокJSONL {
    @Test("Все разбиения сохраняют байты, позиции, SHA, префикс и хвост")
    func всеРазбиенияСохраняютРезультат() throws {
        for данные in короткиеФикстуры {
            let число = try числоРазбиений(данные)
            for маска in 0..<число {
                try сверитьСОдноразовымФасадом(данные, порции: порции(данные, маска: маска),
                    начальноеСмещение: 0)
            }
        }
    }

    @Test("Ненулевое начальное смещение остаётся абсолютным")
    func ненулевоеНачальноеСмещение() throws {
        let данные = Data([0x78, 0x0a, 0x0a, 0x79, 0x0d, 0x0a, 0xff])
        try сверитьСОдноразовымФасадом(данные,
            порции: порции(данные, маска: 0b10_1010), начальноеСмещение: 8_192)
    }

    @Test("Малый профиль полного перебора разбиений")
    func профильПолногоПеребора() throws {
        let повторов = 3
        let разбиения = try короткиеФикстуры.map(числоРазбиений)
        let сканированийВСерии = разбиения.reduce(0, +)
        var длительности: [Int64] = []
        var контроль = 0

        for _ in 0..<повторов {
            let начало = ContinuousClock.now
            for (данные, число) in zip(короткиеФикстуры, разбиения) {
                for маска in 0..<число {
                    let (рамки, итог) = try просканировать(порции(данные, маска: маска),
                        начальноеСмещение: 0)
                    контроль += рамки.count + итог.префикс.байты + итог.сыройХвост.count
                }
            }
            длительности.append(наносекунды(начало.duration(to: ContinuousClock.now)))
        }

        let ожидаемыйКонтроль = try короткиеФикстуры.map { данные in
            let эталон = try выделитьРамкиПотока(данные)
            return try числоРазбиений(данные)
                * (эталон.рамки.count + эталон.префикс.байты + эталон.сыройХвост.count)
        }.reduce(0, +) * повторов
        #expect(контроль == ожидаемыйКонтроль)

        let профиль = ПрофильРазбиений(повторов: повторов,
            разбиенийНаФикстуру: разбиения, сканированийВСерии: сканированийВСерии,
            максимумБайтовВхода: короткиеФикстуры.map(\.count).max() ?? 0,
            наносекунды: длительности)
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        print("ПРОФИЛЬ_ИНВАРИАНТНОСТИ_РАЗБИЕНИЯ_JSONL:"
            + String(decoding: try кодировщик.encode(профиль), as: UTF8.self))
    }
}

private let короткиеФикстуры: [Data] = [
    Data([0x61, 0x0a, 0x0a, 0x62, 0x0a, 0x63]),
    Data([0x64, 0x0d, 0x0a, 0x65, 0x0d, 0x0a, 0x66]),
    Data([0xff, 0x0a, 0x80, 0x0a, 0x0a, 0x67, 0xc3, 0x28])
]

private enum ОшибкаПроверкиРазбиений: Error {
    case недопустимаяФикстура
}

private struct ПрофильРазбиений: Encodable {
    let схема = "fuma.профиль-инвариантности-разбиения-рамок-jsonl.1"
    let повторов: Int
    let разбиенийНаФикстуру: [Int]
    let сканированийВСерии: Int
    let максимумБайтовВхода: Int
    let наносекунды: [Int64]
    let граница = "Три открытые Data-фикстуры до 8 байтов; все непустые разбиения, без файла и RAW. Измерение включает создание последовательного фасада, приём порций, callback и завершение; построение порций и контрольная сумма включены, одноразовый эталон и JSON-кодирование вне интервала. Сравнение скорости и заявление об ускорении не выполнялись."
}

private func числоРазбиений(_ данные: Data) throws -> Int {
    guard !данные.isEmpty, данные.count <= 32 else {
        throw ОшибкаПроверкиРазбиений.недопустимаяФикстура
    }
    let число = 1 << (данные.count - 1)
    guard число <= 4_096 else {
        throw ОшибкаПроверкиРазбиений.недопустимаяФикстура
    }
    return число
}

private func порции(_ данные: Data, маска: Int) -> [Data] {
    var результат: [Data] = []
    var начало = 0
    if данные.count > 1 {
        for граница in 1..<данные.count where маска & (1 << (граница - 1)) != 0 {
            результат.append(Data(данные[начало..<граница]))
            начало = граница
        }
    }
    результат.append(Data(данные[начало..<данные.count]))
    return результат
}

private func просканировать(_ порции: [Data], начальноеСмещение: Int) throws
    -> ([РамкаПотока], ИтогПоследовательныхРамок) {
    let поток = try ПоследовательныеРамкиJSONL(начальноеСмещение: начальноеСмещение)
    var рамки: [РамкаПотока] = []
    var смещение = начальноеСмещение
    for порция in порции {
        смещение = try поток.принять(порция, смещение: смещение) { рамки.append($0) }
    }
    return (рамки, try поток.завершить())
}

private func сверитьСОдноразовымФасадом(_ данные: Data, порции: [Data],
                                        начальноеСмещение: Int) throws {
    let эталон = try выделитьРамкиПотока(данные)
    let (рамки, итог) = try просканировать(порции, начальноеСмещение: начальноеСмещение)

    #expect(рамки.map(\.данные) == эталон.рамки.map(\.данные))
    #expect(рамки.map(\.позиция.номер) == эталон.рамки.map(\.позиция.номер))
    #expect(рамки.map(\.позиция.начало)
        == эталон.рамки.map { $0.позиция.начало + начальноеСмещение })
    #expect(рамки.map(\.позиция.конец)
        == эталон.рамки.map { $0.позиция.конец + начальноеСмещение })
    #expect(рамки.map(\.позиция.sha256) == эталон.рамки.map(\.позиция.sha256))
    #expect(итог.префикс == эталон.префикс)
    #expect(итог.сыройХвост == эталон.сыройХвост)
    #expect(итог.следующееСмещение == начальноеСмещение + данные.count)
    #expect(итог.пикБуфераСтроки == эталон.пикБуфераСтроки)
}

private func наносекунды(_ длительность: Duration) -> Int64 {
    let части = длительность.components
    return части.seconds * 1_000_000_000 + части.attoseconds / 1_000_000_000
}

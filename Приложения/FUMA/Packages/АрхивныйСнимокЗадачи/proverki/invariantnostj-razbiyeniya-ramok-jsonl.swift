private func числоРазбиений(_ данные: Data) throws -> Int {
    guard !данные.isEmpty, данные.count <= 32 else {
        throw ОшибкаПроверкиРазбиений.недопустимаяФикстура
    }
    let число = 1 << (данные.count - 1)
    guard число <= 4_096 else {
        throw ОшибкаПроверкиРазбиений.недопустимаяФикстура
    }
    return число
}

private func порции(_ данные: Data, маска: Int) -> [Data] {
    var результат: [Data] = []
    var начало = 0
    if данные.count > 1 {
        for граница in 1..<данные.count where маска & (1 << (граница - 1)) != 0 {
            результат.append(Data(данные[начало..<граница]))
            начало = граница
        }
    }
    результат.append(Data(данные[начало..<данные.count]))
    return результат
}

private func просканировать(_ порции: [Data], начальноеСмещение: Int) throws
    -> ([РамкаПотока], ИтогПоследовательныхРамок) {
    let поток = try ПоследовательныеРамкиJSONL(начальноеСмещение: начальноеСмещение)
    var рамки: [РамкаПотока] = []
    var смещение = начальноеСмещение
    for порция in порции {
        смещение = try поток.принять(порция, смещение: смещение) { рамки.append($0) }
    }
    return (рамки, try поток.завершить())
}

private func сверитьСЗолотымОракулом(_ фикстура: ЗолотаяФикстура) throws {
    let одноразовый = try выделитьРамкиПотока(фикстура.вход)
    let (последовательныеРамки, последовательныйИтог) = try просканировать(
        [фикстура.вход], начальноеСмещение: 0)

    сверитьСЗолотымОракулом(одноразовый.рамки, префикс: одноразовый.префикс,
        хвост: одноразовый.сыройХвост, пикБуфераСтроки: одноразовый.пикБуфераСтроки,
        фикстура: фикстура)
    сверитьСЗолотымОракулом(последовательныеРамки, префикс: последовательныйИтог.префикс,
        хвост: последовательныйИтог.сыройХвост,
        пикБуфераСтроки: последовательныйИтог.пикБуфераСтроки, фикстура: фикстура)
    #expect(последовательныйИтог.следующееСмещение == фикстура.вход.count)
}

private func сверитьСЗолотымОракулом(_ рамки: [РамкаПотока], префикс: ГраницаПрефикса,
                                     хвост: Data, пикБуфераСтроки: Int,
                                     фикстура: ЗолотаяФикстура) {
    #expect(рамки.map(\.данные) == фикстура.рамки.map(\.данные))
    #expect(рамки.map(\.позиция.номер) == фикстура.рамки.map(\.номер))
    #expect(рамки.map(\.позиция.начало) == фикстура.рамки.map(\.начало))
    #expect(рамки.map { $0.позиция.конец - $0.позиция.начало }
        == фикстура.рамки.map(\.длина))
    #expect(рамки.map(\.позиция.конец)
        == фикстура.рамки.map { $0.начало + $0.длина })
    #expect(рамки.map(\.позиция.sha256)
        == фикстура.рамки.map { золотойSHA256($0.данные) })

    let ожидаемыеБайтыПрефикса = Data(фикстура.рамки.flatMap { $0.данные })
    #expect(ожидаемыеБайтыПрефикса.count == фикстура.префиксБайтов)
    #expect(префикс.байты == фикстура.префиксБайтов)
    #expect(префикс.строки == фикстура.префиксСтрок)
    #expect(префикс.sha256 == золотойSHA256(ожидаемыеБайтыПрефикса))
    #expect(хвост == фикстура.хвост)
    #expect(пикБуфераСтроки == фикстура.пикБуфераСтроки)
}

private func золотойSHA256(_ данные: Data) -> String {
    SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}

private func сверитьСОдноразовымФасадом(_ данные: Data, порции: [Data],
                                        начальноеСмещение: Int) throws {
    let эталон = try выделитьРамкиПотока(данные)
    let (рамки, итог) = try просканировать(порции, начальноеСмещение: начальноеСмещение)

    #expect(рамки.map(\.данные) == эталон.рамки.map(\.данные))
    #expect(рамки.map(\.позиция.номер) == эталон.рамки.map(\.позиция.номер))
    #expect(рамки.map(\.позиция.начало)
        == эталон.рамки.map { $0.позиция.начало + начальноеСмещение })
    #expect(рамки.map(\.позиция.конец)
        == эталон.рамки.map { $0.позиция.конец + начальноеСмещение })
    #expect(рамки.map(\.позиция.sha256) == эталон.рамки.map(\.позиция.sha256))
    #expect(итог.префикс == эталон.префикс)
    #expect(итог.сыройХвост == эталон.сыройХвост)
    #expect(итог.следующееСмещение == начальноеСмещение + данные.count)
    #expect(итог.пикБуфераСтроки == эталон.пикБуфераСтроки)
}

private func наносекунды(_ длительность: Duration) -> Int64 {
    let части = длительность.components
    return части.seconds * 1_000_000_000 + части.attoseconds / 1_000_000_000
}

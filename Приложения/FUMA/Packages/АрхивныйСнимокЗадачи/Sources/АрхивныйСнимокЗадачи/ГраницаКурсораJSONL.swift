import Foundation
import CryptoKit

public enum ОшибкаСверкиРамокJSONL: Error, Equatable, Sendable {
    case отрицательноеСмещение(Int)
    case переполнение
    case повреждённыйКурсор
}

/// Полный доступный байтовый снимок от закреплённого абсолютного смещения.
/// Произвольная старая порция без прежних байтов не доказывает replay.
public struct БайтовыйСрезJSONL: Equatable, Sendable {
    public let начало: Int
    public let данные: Data

    public init(начало: Int, данные: Data) throws {
        guard начало >= 0 else { throw ОшибкаСверкиРамокJSONL.отрицательноеСмещение(начало) }
        self.начало = начало
        self.данные = данные
    }
}

public struct НеполныйХвостJSONL: Equatable, Sendable {
    public let начало: Int
    public let конец: Int
    public let данные: Data
}

/// Переносимая граница уже наблюдённого полного среза.
/// Префикс охватывает только завершённые LF-записи, а хвост сохраняется буквально.
public struct КурсорРамокJSONL: Codable, Equatable, Sendable {
    public let началоСреза: Int
    public let префикс: ГраницаПрефикса
    public let следующееСмещение: Int
    public let неполныйХвост: Data
}

public enum ДрейфРамокJSONL: Equatable, Sendable {
    case несовместимоеНачало(ожидалось: Int, получено: Int)
    case усечение(ожидалосьДо: Int, полученоДо: Int)
    case завершённыйПрефикс(провереноДо: Int)
    case неполныйХвост(начало: Int, конец: Int)
}

public enum ИсходСверкиРамокJSONL: Equatable, Sendable {
    case продолжение(завершённыеЗаписи: [РамкаПотока],
                     неполныйХвост: НеполныйХвостJSONL?,
                     курсор: КурсорРамокJSONL)
    case повтор(курсор: КурсорРамокJSONL)
    case дрейф(ДрейфРамокJSONL)
}

/// Перечитывает доступный срез, сверяет все ранее наблюдённые байты и возвращает
/// только новые завершённые LF-записи. JSON и UTF-8 здесь не интерпретируются.
public func сверитьРамкиJSONL(
    _ срез: БайтовыйСрезJSONL,
    после прежнийКурсор: КурсорРамокJSONL? = nil,
    пределы: ПределыПоследовательныхРамок = ПределыПоследовательныхРамок()
) throws -> ИсходСверкиРамокJSONL {
    let следующееСмещение = try сложитьСмещения(срез.начало, срез.данные.count)
    var пропуститьДо = 0

    if let прежнийКурсор {
        let проверенный = try проверитьКурсор(прежнийКурсор)
        guard прежнийКурсор.началоСреза == срез.начало else {
            return .дрейф(.несовместимоеНачало(
                ожидалось: прежнийКурсор.началоСреза, получено: срез.начало))
        }
        guard следующееСмещение >= прежнийКурсор.следующееСмещение else {
            return .дрейф(.усечение(
                ожидалосьДо: прежнийКурсор.следующееСмещение,
                полученоДо: следующееСмещение))
        }
        guard проверенный.длинаНаблюдения <= срез.данные.count else {
            throw ОшибкаСверкиРамокJSONL.повреждённыйКурсор
        }
        let наблюдённыйПрефикс = хэшироватьНаблюдённыйПрефикс(
            срез.данные, длина: прежнийКурсор.префикс.байты, порция: пределы.порция)
        guard наблюдённыйПрефикс.строки == прежнийКурсор.префикс.строки,
              наблюдённыйПрефикс.sha256 == прежнийКурсор.префикс.sha256 else {
            let провереноДо = try сложитьСмещения(
                прежнийКурсор.началоСреза, прежнийКурсор.префикс.байты)
            return .дрейф(.завершённыйПрефикс(провереноДо: провереноДо))
        }
        guard наблюдённыйПрефикс.завершёнLF else {
            throw ОшибкаСверкиРамокJSONL.повреждённыйКурсор
        }

        let началоХвоста = срез.данные.index(
            срез.данные.startIndex, offsetBy: прежнийКурсор.префикс.байты)
        let конецХвоста = срез.данные.index(
            началоХвоста, offsetBy: прежнийКурсор.неполныйХвост.count)
        let наблюдённыйХвост = срез.данные[началоХвоста..<конецХвоста]
        guard наблюдённыйХвост.elementsEqual(прежнийКурсор.неполныйХвост) else {
            let абсолютноеНачало = try сложитьСмещения(
                прежнийКурсор.началоСреза, прежнийКурсор.префикс.байты)
            return .дрейф(.неполныйХвост(
                начало: абсолютноеНачало, конец: прежнийКурсор.следующееСмещение))
        }
        пропуститьДо = прежнийКурсор.префикс.байты
    }

    let (новыеЗаписи, итог) = try просканироватьГраницу(
        срез, пределы: пределы, пропуститьДо: пропуститьДо)
    let курсор = КурсорРамокJSONL(
        началоСреза: срез.начало,
        префикс: итог.префикс,
        следующееСмещение: следующееСмещение,
        неполныйХвост: итог.сыройХвост)
    if let прежнийКурсор, курсор == прежнийКурсор {
        return .повтор(курсор: курсор)
    }
    let хвост: НеполныйХвостJSONL?
    if итог.сыройХвост.isEmpty {
        хвост = nil
    } else {
        let началоХвоста = try сложитьСмещения(срез.начало, итог.префикс.байты)
        хвост = НеполныйХвостJSONL(
            начало: началоХвоста, конец: следующееСмещение, данные: итог.сыройХвост)
    }
    return .продолжение(
        завершённыеЗаписи: новыеЗаписи, неполныйХвост: хвост, курсор: курсор)
}

private struct ПроверенныйКурсорРамокJSONL {
    let длинаНаблюдения: Int
}

private struct НаблюдённыйПрефиксJSONL {
    let строки: Int
    let sha256: String
    let завершёнLF: Bool
}

private func проверитьКурсор(_ курсор: КурсорРамокJSONL) throws
    -> ПроверенныйКурсорРамокJSONL {
    guard курсор.началоСреза >= 0,
          курсор.префикс.байты >= 0,
          курсор.префикс.строки >= 0,
          курсор.префикс.байты >= курсор.префикс.строки,
          проверитьХэшГраницы(курсор.префикс.sha256),
          !курсор.неполныйХвост.contains(0x0a) else {
        throw ОшибкаСверкиРамокJSONL.повреждённыйКурсор
    }
    if курсор.префикс.строки == 0 {
        guard курсор.префикс.байты == 0,
              курсор.префикс.sha256 == хэшАрхива(Data()) else {
            throw ОшибкаСверкиРамокJSONL.повреждённыйКурсор
        }
    }
    let конецПрефикса = try сложитьСмещения(
        курсор.началоСреза, курсор.префикс.байты)
    let ожидаемоеСледующее = try сложитьСмещения(
        конецПрефикса, курсор.неполныйХвост.count)
    guard ожидаемоеСледующее == курсор.следующееСмещение else {
        throw ОшибкаСверкиРамокJSONL.повреждённыйКурсор
    }
    let (длинаНаблюдения, переполнение) = курсор.следующееСмещение
        .subtractingReportingOverflow(курсор.началоСреза)
    guard !переполнение, длинаНаблюдения >= 0 else {
        throw ОшибкаСверкиРамокJSONL.повреждённыйКурсор
    }
    return ПроверенныйКурсорРамокJSONL(длинаНаблюдения: длинаНаблюдения)
}

private func просканироватьГраницу(
    _ срез: БайтовыйСрезJSONL,
    пределы: ПределыПоследовательныхРамок,
    пропуститьДо: Int
) throws -> ([РамкаПотока], ИтогСканераПотока) {
    var бюджет = БюджетАрхива()
    бюджет.байты = пределы.байты
    бюджет.строка = пределы.строка
    бюджет.строки = пределы.рамки
    let сканер = СканерРамокПотока(бюджет: бюджет, прежняя: nil)
    var рамки: [РамкаПотока] = []
    var начало = срез.данные.startIndex
    while начало < срез.данные.endIndex {
        let осталось = срез.данные.distance(from: начало, to: срез.данные.endIndex)
        let конец = срез.данные.index(
            начало, offsetBy: min(пределы.порция, осталось))
        let порция = Data(срез.данные[начало..<конец])
        try порция.withUnsafeBytes { сырые in
            try сканер.принять(сырые.bindMemory(to: UInt8.self)) { данные, позиция in
                guard позиция.конец > пропуститьДо else { return }
                let абсолютноеНачало = try сложитьСмещения(срез.начало, позиция.начало)
                let абсолютныйКонец = try сложитьСмещения(срез.начало, позиция.конец)
                рамки.append(РамкаПотока(
                    данные: данные,
                    позиция: ПозицияСтроки(
                        номер: позиция.номер,
                        начало: абсолютноеНачало,
                        конец: абсолютныйКонец,
                        sha256: позиция.sha256)))
            }
        }
        начало = конец
    }
    return (рамки, try сканер.завершить())
}

private func хэшироватьНаблюдённыйПрефикс(
    _ данные: Data,
    длина: Int,
    порция: Int
) -> НаблюдённыйПрефиксJSONL {
    var хэш = SHA256()
    var строки = 0
    var смещение = 0
    while смещение < длина {
        let число = min(порция, длина - смещение)
        let начало = данные.index(данные.startIndex, offsetBy: смещение)
        let конец = данные.index(начало, offsetBy: число)
        let часть = данные[начало..<конец]
        хэш.update(data: часть)
        строки += часть.lazy.filter { $0 == 0x0a }.count
        смещение += число
    }
    let sha256 = хэш.finalize().map { String(format: "%02x", $0) }.joined()
    let завершёнLF: Bool
    if длина == 0 {
        завершёнLF = true
    } else {
        let последний = данные.index(данные.startIndex, offsetBy: длина - 1)
        завершёнLF = данные[последний] == 0x0a
    }
    return НаблюдённыйПрефиксJSONL(
        строки: строки, sha256: sha256, завершёнLF: завершёнLF)
}

private func сложитьСмещения(_ левое: Int, _ правое: Int) throws -> Int {
    let (значение, переполнение) = левое.addingReportingOverflow(правое)
    guard !переполнение else { throw ОшибкаСверкиРамокJSONL.переполнение }
    return значение
}

private func проверитьХэшГраницы(_ строка: String) -> Bool {
    строка.utf8.count == 64 && строка.utf8.allSatisfy {
        (48...57).contains($0) || (97...102).contains($0)
    }
}

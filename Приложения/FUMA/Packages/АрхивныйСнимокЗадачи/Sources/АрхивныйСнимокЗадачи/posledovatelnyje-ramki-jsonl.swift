import Foundation

/// Логические пределы последовательного фасада. В памяти удерживаются только
/// текущая строка и переданная порция; общий предел сам по себе память не выделяет.
public struct ПределыПоследовательныхРамок: Equatable, Sendable {
    public let порция: Int
    public let строка: Int
    public let рамки: Int
    public let байты: Int

    public init() {
        порция = 1_048_576
        строка = 262_144
        рамки = 1_000_000
        байты = 256 * 1024 * 1024
    }

    public init(порция: Int = 1_048_576, строка: Int = 262_144,
                рамки: Int = 1_000_000, байты: Int = 256 * 1024 * 1024) throws {
        guard (1...1_048_576).contains(порция), (1...262_144).contains(строка),
              рамки > 0, байты > 0 else { throw ОшибкаАрхива.предел }
        self.порция = порция
        self.строка = строка
        self.рамки = рамки
        self.байты = байты
    }
}

public enum ОшибкаПоследовательныхРамок: Error, Equatable, Sendable {
    case отрицательноеСмещение(Int)
    case староеСмещение(ожидалось: Int, получено: Int)
    case разрывСмещения(ожидалось: Int, получено: Int)
    case переполнение
    case повторныйВход
    case завершён
    case отказ
}

public struct ИтогПоследовательныхРамок: Equatable, Sendable {
    /// Число и SHA полных LF-рамок относительно начала этого экземпляра.
    public let префикс: ГраницаПрефикса
    public let сыройХвост: Data
    /// Абсолютное смещение сразу после всех успешно принятых порций.
    public let следующееСмещение: Int
    /// Максимальная длина текущей строки вместе с LF либо хвоста; это не RSS.
    public let пикБуфераСтроки: Int
}

/// Однопроходный синхронный Data/offset-фасад над общим LF-сканером.
/// Экземпляр не поддерживает конкурентные вызовы. Любая ошибка терминальна:
/// уже выданные callback рамки не откатываются, а слепой повтор запрещён.
public final class ПоследовательныеРамкиJSONL {
    private enum Состояние { case открыт, принимает, завершён, отказ }

    private let начальноеСмещение: Int
    private let пределы: ПределыПоследовательныхРамок
    private let сканер: СканерРамокПотока
    private var следующееСмещение: Int
    private var состояние = Состояние.открыт

    public init(начальноеСмещение: Int = 0,
                пределы: ПределыПоследовательныхРамок = ПределыПоследовательныхРамок()) throws {
        guard начальноеСмещение >= 0 else {
            throw ОшибкаПоследовательныхРамок.отрицательноеСмещение(начальноеСмещение)
        }
        self.начальноеСмещение = начальноеСмещение
        self.пределы = пределы
        self.следующееСмещение = начальноеСмещение
        var бюджет = БюджетАрхива()
        бюджет.байты = пределы.байты
        бюджет.строка = пределы.строка
        бюджет.строки = пределы.рамки
        сканер = СканерРамокПотока(бюджет: бюджет, прежняя: nil)
    }

    /// Принимает ровно следующую порцию и возвращает ожидаемое смещение новой порции.
    /// Смещение проверяется до любого callback. Старые байты без внешней RAW-сверки
    /// не считаются повтором и закрывают экземпляр отказом.
    @discardableResult
    public func принять(_ данные: Data, смещение: Int,
                        принять: (РамкаПотока) throws -> Void) throws -> Int {
        try требоватьОткрытое()
        do {
            if смещение < следующееСмещение {
                throw ОшибкаПоследовательныхРамок.староеСмещение(
                    ожидалось: следующееСмещение, получено: смещение)
            }
            if смещение > следующееСмещение {
                throw ОшибкаПоследовательныхРамок.разрывСмещения(
                    ожидалось: следующееСмещение, получено: смещение)
            }
            guard данные.count <= пределы.порция else { throw ОшибкаАрхива.предел }
            let (новоеСмещение, переполнение) = следующееСмещение.addingReportingOverflow(данные.count)
            guard !переполнение else { throw ОшибкаПоследовательныхРамок.переполнение }
            состояние = .принимает
            try данные.withUnsafeBytes { сырые in
                try сканер.принять(сырые.bindMemory(to: UInt8.self)) { [self] строка, позиция in
                    guard состояние == .принимает else { throw ОшибкаПоследовательныхРамок.отказ }
                    let начало = try абсолютноеСмещение(позиция.начало)
                    let конец = try абсолютноеСмещение(позиция.конец)
                    try принять(РамкаПотока(данные: строка,
                        позиция: ПозицияСтроки(номер: позиция.номер, начало: начало,
                            конец: конец, sha256: позиция.sha256)))
                    guard состояние == .принимает else { throw ОшибкаПоследовательныхРамок.отказ }
                }
            }
            guard состояние == .принимает else { throw ОшибкаПоследовательныхРамок.отказ }
            следующееСмещение = новоеСмещение
            состояние = .открыт
            return новоеСмещение
        } catch {
            состояние = .отказ
            throw error
        }
    }

    public func завершить() throws -> ИтогПоследовательныхРамок {
        try требоватьОткрытое()
        do {
            let итог = try сканер.завершить()
            состояние = .завершён
            return ИтогПоследовательныхРамок(префикс: итог.префикс,
                сыройХвост: итог.сыройХвост, следующееСмещение: следующееСмещение,
                пикБуфераСтроки: итог.пикБуфераСтроки)
        } catch {
            состояние = .отказ
            throw error
        }
    }

    private func требоватьОткрытое() throws {
        switch состояние {
        case .открыт: return
        case .принимает:
            состояние = .отказ
            throw ОшибкаПоследовательныхРамок.повторныйВход
        case .завершён: throw ОшибкаПоследовательныхРамок.завершён
        case .отказ: throw ОшибкаПоследовательныхРамок.отказ
        }
    }

    private func абсолютноеСмещение(_ относительное: Int) throws -> Int {
        let (значение, переполнение) = начальноеСмещение.addingReportingOverflow(относительное)
        guard !переполнение else { throw ОшибкаПоследовательныхРамок.переполнение }
        return значение
    }
}

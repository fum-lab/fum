import XCTest
import Foundation
import СнимокАгентскойЗадачи
@testable import АрхивныйСнимокЗадачи

final class ПроисхождениеTests: XCTestCase, @unchecked Sendable {
    func testReplayНеПринимаетПротиворечивыеПозиции() async throws {
        let пример = try Фикстура(); defer { пример.убрать() }
        try пример.записать([мета(), контекст()])
        let архив = try пример.открыть(); let исходный = try await архив.импортировать(пример.источник); await архив.закрыть()
        let принятый = исходный.архив
        let модель = try XCTUnwrap(принятый.модельХода)
        for вид in 0..<3 {
            let номер = вид == 2 ? 1 : модель.позиция.номер
            let позиция = ПозицияСтроки(номер: номер, начало: вид == 1 ? 0 : модель.позиция.начало,
                конец: модель.позиция.конец, sha256: вид == 0 ? String(repeating: "a", count: 64) : модель.позиция.sha256)
            let выбор = ВыборФактов(sessionMeta: принятый.sessionMeta, каталогRuntime: принятый.каталогRuntime,
                последнийХод: принятый.последнийХод, модельХода: ФактСтроки(значение: модель.значение, позиция: позиция))
            let подмена = try собратьРезультат(uuidФикстуры, выбор, принятый.граница, nil)
            XCTAssertThrowsError(try восстановитьРезультат(каноническийJSON(подмена.архив), uuid: uuidФикстуры, прежний: nil, бюджет: .init()))
        }
    }
    func testReplayНеПереноситПрежнююМодельЧерезЦепочку() async throws {
        let пример = try Фикстура(); defer { пример.убрать() }
        try пример.записать([мета(), контекст()])
        let архив = try пример.открыть(); let первый = try await архив.импортировать(пример.источник)
        try пример.записать([мета(), контекст(), контекст(ходВторой, модель: nil)])
        let второй = try await архив.импортировать(пример.источник); await архив.закрыть()
        let выбор = ВыборФактов(sessionMeta: второй.архив.sessionMeta, каталогRuntime: второй.архив.каталогRuntime,
            последнийХод: второй.архив.последнийХод, модельХода: первый.архив.модельХода)
        let подмена = try собратьРезультат(uuidФикстуры, выбор, второй.архив.граница, второй.архив.предыдущийSHA)
        XCTAssertThrowsError(try восстановитьРезультат(каноническийJSON(подмена.архив), uuid: uuidФикстуры, прежний: первый.архив, бюджет: .init()))
    }
}

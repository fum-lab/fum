import XCTest
import Foundation
import КонтейнерНаблюдений
import СнимокАгентскойЗадачи
@testable import АрхивныйСнимокЗадачи

final class КурсорTests: XCTestCase, @unchecked Sendable {
    private let пустоеСобытие = "{\"type\":\"event_msg\",\"payload\":{}}"

    private func импорт(_ пример: Фикстура, _ строки: [String]) async throws -> АрхивноеНаблюдение {
        try пример.записать(строки)
        let архив = try пример.открыть()
        let результат = try await архив.импортировать(пример.источник)
        await архив.закрыть()
        try FileManager.default.removeItem(at: пример.источник)
        return результат.архив
    }
    private func выбор(_ архив: АрхивноеНаблюдение) -> ВыборФактов {
        ВыборФактов(sessionMeta: архив.sessionMeta, каталогRuntime: архив.каталогRuntime,
                    последнийХод: архив.последнийХод, модельХода: архив.модельХода)
    }
    private func проверитьReplay(_ объекты: [АрхивноеНаблюдение], пример: Фикстура,
                                 допустим: Bool, бюджет: БюджетАрхива = .init(),
                                 file: StaticString = #filePath, line: UInt = #line) async throws {
        let каталог = пример.корень.appendingPathComponent("replay-" + UUID().uuidString)
        try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: true)
        let контейнер = try Сегмент(кореньДанных: каталог, запись: true, создать: true)
        do {
            for объект in объекты { _ = try контейнер.добавить(описаниеАрхива(объект), данные: каноническийJSON(объект)) }
            контейнер.закрыть()
        } catch { контейнер.закрыть(); throw error }
        do {
            let архив = try АрхивЗадачи(корень: каталог, ожидаемыйUUID: uuidФикстуры, запись: false, бюджет: бюджет)
            let результат = try await архив.получить(); await архив.закрыть()
            if допустим { XCTAssertEqual(результат?.архив, объекты.last, file: file, line: line) }
            else { XCTFail("replay принял канонический невыполнимый курсор", file: file, line: line) }
        } catch {
            if допустим { XCTFail("replay отклонил допустимые пропуски: \(error)", file: file, line: line) }
            else { XCTAssertEqual(error as? ОшибкаАрхива, .повреждениеАрхива, file: file, line: line) }
        }
    }
    func testReplayНеПринимаетСтрокуБезБайтовПослеМета() async throws {
        let пример = try Фикстура(); defer { пример.убрать() }
        let исходный = try await импорт(пример, [мета()])
        let граница = ГраницаПрефикса(байты: исходный.граница.байты, строки: 2, sha256: исходный.граница.sha256)
        let подмена = try собратьРезультат(uuidФикстуры, выбор(исходный), граница, nil).архив
        try await проверитьReplay([подмена], пример: пример, допустим: false)
    }
    func testReplayСоблюдаетМинимальнуюДлинуИдентичности() async throws {
        let пример = try Фикстура(); defer { пример.убрать() }
        let строка = "{\"type\":\"session_meta\",\"payload\":{\"id\":\"" + uuidФикстуры + "\"}}"
        let исходный = try await импорт(пример, [строка])
        XCTAssertEqual(исходный.граница.байты, 80)
        try await проверитьReplay([исходный], пример: пример, допустим: true)
        let позиция = ПозицияСтроки(номер: 1, начало: 0, конец: 79, sha256: исходный.sessionMeta.позиция.sha256)
        let факты = ВыборФактов(sessionMeta: ИдентичностьСессии(uuid: uuidФикстуры, позиция: позиция))
        let граница = ГраницаПрефикса(байты: 79, строки: 1, sha256: исходный.граница.sha256)
        let подмена = try собратьРезультат(uuidФикстуры, факты, граница, nil).архив
        try await проверитьReplay([подмена], пример: пример, допустим: false)
    }
    func testReplayПроверяетНевыбранныеПромежуткиИХвосты() async throws {
        let пример = try Фикстура(); defer { пример.убрать() }
        let исходный = try await импорт(пример, [мета(), пустоеСобытие, контекст(), пустоеСобытие])
        let факт = try XCTUnwrap(исходный.последнийХод)
        let длина = факт.позиция.конец - факт.позиция.начало
        var бюджет = БюджетАрхива(); бюджет.строка = 512
        // номер выбранной строки, байты перед ней, число и байты невыбранного хвоста.
        let случаи = [(2, 1, 0, 0), (3, 0, 0, 0), (3, 33, 0, 0), (3, 513, 0, 0),
                       (3, 34, 1, 0), (3, 34, 1, 33), (3, 34, 1, 513), (3, 34, 0, 1)]
        for (номер, промежуток, строкиХвоста, хвост) in случаи {
            let начало = исходный.sessionMeta.позиция.конец + промежуток
            let позиция = ПозицияСтроки(номер: номер, начало: начало, конец: начало + длина, sha256: факт.позиция.sha256)
            var факты = выбор(исходный)
            факты.последнийХод = ФактСтроки(значение: факт.значение, позиция: позиция)
            факты.модельХода = ФактСтроки(значение: try XCTUnwrap(исходный.модельХода).значение, позиция: позиция)
            let граница = ГраницаПрефикса(байты: позиция.конец + хвост, строки: номер + строкиХвоста, sha256: исходный.граница.sha256)
            let подмена = try собратьРезультат(uuidФикстуры, факты, граница, nil).архив
            try await проверитьReplay([подмена], пример: пример, допустим: false, бюджет: бюджет)
        }
    }
    func testReplayУчитываетГраницуПрежнегоОбъектаВПромежутках() async throws {
        let пример = try Фикстура(); defer { пример.убрать() }
        let первый = try await импорт(пример, [мета(), пустоеСобытие])
        let второй = try await импорт(пример, [мета(), пустоеСобытие, контекст()])
        let ход = try XCTUnwrap(второй.последнийХод)
        for смещение in [-1, 1] {
            let позиция = ПозицияСтроки(номер: ход.позиция.номер, начало: ход.позиция.начало + смещение,
                конец: ход.позиция.конец + смещение, sha256: ход.позиция.sha256)
            var факты = выбор(второй)
            факты.последнийХод = ФактСтроки(значение: ход.значение, позиция: позиция)
            факты.модельХода = ФактСтроки(значение: try XCTUnwrap(второй.модельХода).значение, позиция: позиция)
            let граница = ГраницаПрефикса(байты: второй.граница.байты + смещение, строки: второй.граница.строки, sha256: второй.граница.sha256)
            let подмена = try собратьРезультат(uuidФикстуры, факты, граница, второй.предыдущийSHA).архив
            try await проверитьReplay([первый, подмена], пример: пример, допустим: false)
        }
        let граница = ГраницаПрефикса(байты: первый.граница.байты + 1, строки: первый.граница.строки + 1, sha256: второй.граница.sha256)
        let подмена = try собратьРезультат(uuidФикстуры, выбор(первый), граница, второй.предыдущийSHA).архив
        try await проверитьReplay([первый, подмена], пример: пример, допустим: false)
    }
    func testReplayСохраняетДопустимыеНевыбранныеСтрокиИЦепочки() async throws {
        for длина in [34, 512] {
            let пример = try Фикстура(); defer { пример.убрать() }
            var бюджет = БюджетАрхива(); бюджет.строка = 512
            let событие = пустоеСобытие + String(repeating: " ", count: длина - 34)
            let первый = try await импорт(пример, [мета(), событие])
            let второй = try await импорт(пример, [мета(), событие, событие, контекст(), событие, событие])
            try await проверитьReplay([первый, второй], пример: пример, допустим: true, бюджет: бюджет)
        }
        let пример = try Фикстура(); defer { пример.убрать() }
        let один = try await импорт(пример, [мета()])
        try await проверитьReplay([один], пример: пример, допустим: true)
    }
}

import Darwin
import Foundation
import Testing
import КонтейнерНаблюдений
@testable import СигналВходаФайловойСистемы

@Suite("Сигнал нового файла верхнего уровня")
struct ПроверкиСигналаВхода {
    @Test("Новая запись даёт один сигнал с исходными байтами и парной provenance")
    func новаяЗаписьСохраняетГраницуИБайты() throws {
        let корень = try создатьВременныйКорень("сигнал-добавление")
        defer { try? FileManager.default.removeItem(at: корень) }

        let источник = "fixture:сигнал-входа"
        let прежний = try НаблюдениеФайловойСистемы.наблюдать(
            корень: корень,
            источник: источник)
        let имя = "вход-0001.bin"
        let байты = Data([0x00, 0x7f, 0xc3, 0xa9, 0xff, 0x0a])
        try байты.write(to: корень.appendingPathComponent(имя))
        try FileManager.default.setAttributes(
            [.posixPermissions: 0o600],
            ofItemAtPath: корень.appendingPathComponent(имя).path)
        let новый = try НаблюдениеФайловойСистемы.наблюдать(
            корень: корень,
            источник: источник,
            предшественник: прежний)

        let граница = ОжидаемаяГраницаВхода(
            источник: источник,
            физическийКорень: новый.физическийКорень,
            владелец: UInt32(geteuid()))
        let исход = СигналВходаФайловойСистемы.получить(
            между: прежний,
            и: новый,
            ожидая: граница)
        guard case .сигнал(let сигнал) = исход else {
            Issue.record("Для одного нового обычного файла ожидался сигнал.")
            return
        }
        #expect(сигнал.имя == имя)
        #expect(сигнал.байты == байты)
        #expect(сигнал.источник == источник)
        #expect(сигнал.корень == новый.физическийКорень)
        #expect(сигнал.идентификаторПредшественника == прежний.идентификатор)
        #expect(сигнал.идентификаторСнимка == новый.идентификатор)
        #expect(сигнал.владелец == UInt32(geteuid()))
        #expect(сигнал.режим == 0o600)
        #expect(сигнал.границаСогласованности == новый.границаСогласованности)
        #expect(сигнал.границаСогласованности == .объектыПровереныПоОтдельностиОбщаяАтомарностьНеДоказана)
        let запись = try #require(новый.записи.first(where: { $0.путь == имя }))
        #expect(сигнал.режим == запись.режим)
        #expect(сигнал.хэшБайтов == запись.хэш)
    }

    @Test("Повторная проекция той же пары снимков детерминирована")
    func повторТойЖеПары() throws {
        let пара = try параСОднимДобавленнымФайлом("сигнал-повтор")
        defer { try? FileManager.default.removeItem(at: пара.корень) }
        #expect(
            СигналВходаФайловойСистемы.получить(
                между: пара.прежний,
                и: пара.новый,
                ожидая: пара.граница)
                == СигналВходаФайловойСистемы.получить(
                    между: пара.прежний,
                    и: пара.новый,
                    ожидая: пара.граница))
    }

    @Test("Разрыв predecessor и конфликт источника остаются UNKNOWN")
    func несогласованнаяПараНеДаётСигнала() throws {
        let корень = try создатьВременныйКорень("сигнал-разрыв")
        defer { try? FileManager.default.removeItem(at: корень) }
        let прежний = try НаблюдениеФайловойСистемы.наблюдать(
            корень: корень,
            источник: "fixture:источник-а")
        try Data("новый файл".utf8).write(to: корень.appendingPathComponent("сигнал.txt"))
        try FileManager.default.setAttributes(
            [.posixPermissions: 0o600],
            ofItemAtPath: корень.appendingPathComponent("сигнал.txt").path)
        let безПредшественника = try НаблюдениеФайловойСистемы.наблюдать(
            корень: корень,
            источник: "fixture:источник-а")
        let другойИсточник = try НаблюдениеФайловойСистемы.наблюдать(
            корень: корень,
            источник: "fixture:источник-б")

        let граница = ОжидаемаяГраницаВхода(
            источник: "fixture:источник-а",
            физическийКорень: прежний.физическийКорень,
            владелец: UInt32(geteuid()))
        #expect(
            СигналВходаФайловойСистемы.получить(
                между: прежний,
                и: безПредшественника,
                ожидая: граница)
                == .неизвестно(.несогласованныеСнимки))
        #expect(
            СигналВходаФайловойСистемы.получить(
                между: прежний,
                и: другойИсточник,
                ожидая: граница)
                == .неизвестно(.ожидаемыйИсточникНеСовпадает))
    }

    @Test("Чужие ожидаемые источник, корень или владелец остаются UNKNOWN")
    func чужаяОжидаемаяГраницаНеДаётСигнала() throws {
        let пара = try параСОднимДобавленнымФайлом("сигнал-чужая-граница")
        defer { try? FileManager.default.removeItem(at: пара.корень) }

        let другойКорень = пара.корень.appendingPathComponent("другой-корень", isDirectory: true)
        let другойВладелец = UInt32(geteuid()) ^ 1
        #expect(
            СигналВходаФайловойСистемы.получить(
                между: пара.прежний,
                и: пара.новый,
                ожидая: ОжидаемаяГраницаВхода(
                    источник: "fixture:чужой-источник",
                    физическийКорень: пара.корень,
                    владелец: UInt32(geteuid())))
                == .неизвестно(.ожидаемыйИсточникНеСовпадает))
        #expect(
            СигналВходаФайловойСистемы.получить(
                между: пара.прежний,
                и: пара.новый,
                ожидая: ОжидаемаяГраницаВхода(
                    источник: пара.граница.источник,
                    физическийКорень: другойКорень,
                    владелец: UInt32(geteuid())))
                == .неизвестно(.ожидаемыйКореньНеСовпадает))
        #expect(
            СигналВходаФайловойСистемы.получить(
                между: пара.прежний,
                и: пара.новый,
                ожидая: ОжидаемаяГраницаВхода(
                    источник: пара.граница.источник,
                    физическийКорень: пара.корень,
                    владелец: другойВладелец))
                == .неизвестно(.ожидаемыйВладелецНеСовпадает))
    }

    @Test("Новая относительная ссылка без байтового payload не становится сигналом файла")
    func недоступныйPayloadОстаётсяНеизвестным() throws {
        let корень = try создатьВременныйКорень("сигнал-ссылка")
        defer { try? FileManager.default.removeItem(at: корень) }
        let цель = корень.appendingPathComponent("цель.txt")
        try Data("цель".utf8).write(to: цель)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: цель.path)
        let источник = "fixture:ссылка-не-payload"
        let прежний = try НаблюдениеФайловойСистемы.наблюдать(корень: корень, источник: источник)
        let адресСсылки = корень.appendingPathComponent("вход")
        #expect(symlink("цель.txt", адресСсылки.path) == 0)
        let новый = try НаблюдениеФайловойСистемы.наблюдать(
            корень: корень,
            источник: источник,
            предшественник: прежний)

        #expect(
            СигналВходаФайловойСистемы.получить(
                между: прежний,
                и: новый,
                ожидая: ОжидаемаяГраницаВхода(
                    источник: источник,
                    физическийКорень: новый.физическийКорень,
                    владелец: UInt32(geteuid())))
                == .неизвестно(.недоступныБайты))
    }
}

private struct ПараСнимков {
    let корень: URL
    let прежний: СнимокФайловойСистемы
    let новый: СнимокФайловойСистемы
    let граница: ОжидаемаяГраницаВхода
}

private func параСОднимДобавленнымФайлом(_ имяКорня: String) throws -> ПараСнимков {
    let корень = try создатьВременныйКорень(имяКорня)
    let источник = "fixture:\(имяКорня)"
    let прежний = try НаблюдениеФайловойСистемы.наблюдать(корень: корень, источник: источник)
    let файл = корень.appendingPathComponent("вход.bin")
    try Data([0xde, 0xad, 0x00, 0xbe, 0xef]).write(to: файл)
    try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: файл.path)
    let новый = try НаблюдениеФайловойСистемы.наблюдать(
        корень: корень,
        источник: источник,
        предшественник: прежний)
    let граница = ОжидаемаяГраницаВхода(
        источник: источник,
        физическийКорень: новый.физическийКорень,
        владелец: UInt32(geteuid()))
    return ПараСнимков(корень: корень, прежний: прежний, новый: новый, граница: граница)
}

private func создатьВременныйКорень(_ имя: String) throws -> URL {
    let корень = FileManager.default.temporaryDirectory.appendingPathComponent(
        "\(имя)-\(UUID().uuidString)",
        isDirectory: true)
    try FileManager.default.createDirectory(
        at: корень,
        withIntermediateDirectories: false,
        attributes: [.posixPermissions: 0o700])
    return корень
}

import Foundation
import КонтейнерНаблюдений

/// Явно заданные границы, которым должны соответствовать оба снимка и новый файл.
public struct ОжидаемаяГраницаВхода: Equatable, Sendable {
    public let источник: String
    public let физическийКорень: URL
    public let владелец: UInt32

    public init(источник: String, физическийКорень: URL, владелец: UInt32) {
        self.источник = источник
        self.физическийКорень = физическийКорень
        self.владелец = владелец
    }
}

/// Непрозрачное указание на один новый обычный файл верхнего уровня.
/// Сигнал сообщает о входе, но не подтверждает его приём, обработку или исполнение.
public struct СигналВходящегоФайла: Equatable, Sendable {
    public let источник: String
    public let корень: URL
    public let идентификаторПредшественника: String
    public let идентификаторСнимка: String
    public let имя: String
    public let владелец: UInt32
    public let режим: UInt16
    public let хэшБайтов: String
    public let байты: Data
    public let границаСогласованности: ГраницаСогласованностиСнимкаФайловойСистемы
}

public enum ПричинаНеизвестногоСигнала: String, Equatable, Sendable {
    case несогласованныеСнимки
    case ожидаемыйИсточникНеСовпадает
    case ожидаемыйКореньНеСовпадает
    case ожидаемыйВладелецНеСовпадает
    case неЕдинственноеИзменение
    case нетНовогоФайла
    case имяНеВерхнегоУровня
    case отсутствуетЗаписьНовогоСнимка
    case добавленНеФайл
    case недоступныБайты
}

public enum РезультатСигналаВхода: Equatable, Sendable {
    case сигнал(СигналВходящегоФайла)
    case неизвестно(ПричинаНеизвестногоСигнала)
}

/// Проецирует пару явных снимков в один сигнал нового файла без побочных эффектов.
public enum СигналВходаФайловойСистемы {
    public static func получить(
        между предшественником: СнимокФайловойСистемы,
        и новымСнимком: СнимокФайловойСистемы,
        ожидая ожидаемуюГраницу: ОжидаемаяГраницаВхода
    ) -> РезультатСигналаВхода {
        guard !ожидаемаяГраница.источник.isEmpty,
              ожидаемаяГраница.источник.utf8.count <= 256,
              предшественником.источник == ожидаемаяГраница.источник,
              новымСнимком.источник == ожидаемаяГраница.источник else {
            return .неизвестно(.ожидаемыйИсточникНеСовпадает)
        }
        guard ожидаемаяГраница.физическийКорень.isFileURL,
              ожидаемаяГраница.физическийКорень.path.hasPrefix("/"),
              ожидаемаяГраница.физическийКорень.path
                == ожидаемаяГраница.физическийКорень.standardizedFileURL.path,
              предшественником.физическийКорень == ожидаемаяГраница.физическийКорень,
              новымСнимком.физическийКорень == ожидаемаяГраница.физическийКорень else {
            return .неизвестно(.ожидаемыйКореньНеСовпадает)
        }

        let изменения: [ИзменениеФайловойСистемы]
        do {
            изменения = try НаблюдениеФайловойСистемы.сравнить(
                прежний: предшественником,
                новый: новымСнимком)
        } catch {
            return .неизвестно(.несогласованныеСнимки)
        }

        guard изменения.count == 1, let изменение = изменения.first else {
            return .неизвестно(.неЕдинственноеИзменение)
        }
        guard изменение.вид == .добавлен else {
            return .неизвестно(.нетНовогоФайла)
        }
        guard !изменение.путь.isEmpty,
              изменение.путь != ".",
              изменение.путь != "..",
              !изменение.путь.contains("/"),
              !изменение.путь.utf8.contains(0) else {
            return .неизвестно(.имяНеВерхнегоУровня)
        }
        guard let запись = новымСнимком.записи.first(where: { $0.путь == изменение.путь }) else {
            return .неизвестно(.отсутствуетЗаписьНовогоСнимка)
        }
        guard изменение.новыйХэш == запись.хэш else {
            return .неизвестно(.несогласованныеСнимки)
        }
        guard let байты = запись.содержимое else {
            return .неизвестно(.недоступныБайты)
        }
        guard запись.тип == .файл else {
            return .неизвестно(.добавленНеФайл)
        }
        guard запись.владелец == ожидаемаяГраница.владелец else {
            return .неизвестно(.ожидаемыйВладелецНеСовпадает)
        }

        return .сигнал(СигналВходящегоФайла(
            источник: новымСнимком.источник,
            корень: новымСнимком.физическийКорень,
            идентификаторПредшественника: предшественником.идентификатор,
            идентификаторСнимка: новымСнимком.идентификатор,
            имя: запись.путь,
            владелец: запись.владелец,
            режим: запись.режим,
            хэшБайтов: запись.хэш,
            байты: байты,
            границаСогласованности: новымСнимком.границаСогласованности))
    }
}

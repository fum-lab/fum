        let назначение = try адрес("fum", "target")
        let каталог = try создатьКаталог(
            корень: корень,
            владелецКорня: "coordinator",
            узлы: [
                (источник, "owner-origin", "origin.json", хэш("a")),
                (назначение, "owner-target", "target.json", хэш("b"))
            ])
        let план = try РаспределительЛокальнойОчереди.упорядочить(
            [задание("task", назначение, "owner-target", [], 1)],

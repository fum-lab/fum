    }

    @Test("Подготовленный индекс считает структурную работу для каталогов из 64 и 128 узлов")
    func масштабированиеИндекса() throws {
        let первыйРазмер = 64
        let второйРазмер = первыйРазмер * 2
        let первыйСнимок = try создатьКаталогСУзлами(числоУзлов: первыйРазмер)
        let второйСнимок = try создатьКаталогСУзлами(числоУзлов: второйРазмер)
        let первыйИндекс = try ИндексЛокальнойОчереди(
            каталог: первыйСнимок.каталог,
            исходныйАдрес: первыйСнимок.исходныйАдрес)
        let второйИндекс = try ИндексЛокальнойОчереди(
            каталог: второйСнимок.каталог,
            исходныйАдрес: второйСнимок.исходныйАдрес)
        let первыеЗадания = создатьЗадания(для: первыйСнимок.каталог)
        let вторыеЗадания = создатьЗадания(для: второйСнимок.каталог)
        let первыйРезультат = try РаспределительЛокальнойОчереди.упорядочитьСПодсчётом(
            первыеЗадания, по: первыйИндекс)
        let повторныйРезультат = try РаспределительЛокальнойОчереди.упорядочитьСПодсчётом(
            первыеЗадания, по: первыйИндекс)
        let второйРезультат = try РаспределительЛокальнойОчереди.упорядочитьСПодсчётом(
            вторыеЗадания, по: второйИндекс)
        let перваяРабота = первыйРезультат.счётчикРаботы
        let втораяРабота = второйРезультат.счётчикРаботы
        let дочерниеАдреса = первыйИндекс.дочерниеАдреса(первыйСнимок.исходныйАдрес)

        #expect(дочерниеАдреса.count == первыйРазмер - 1)
        #expect(первыйРезультат == повторныйРезультат)
        #expect(перваяРабота.построенныхУзловИндекса == первыйРазмер)
        #expect(перваяРабота.построенныхХэшейИндекса == первыйРазмер - 1)
        #expect(перваяРабота.построенныхСвязейИндекса == первыйРазмер - 1)
        #expect(перваяРабота.посещённыхВершин == первыйРазмер)
        #expect(перваяРабота.просмотренныхРёбер == 2 * (первыйРазмер - 1))
        #expect(перваяРабота.подготовкаИндекса == 6 * первыйРазмер - 4)
        #expect(перваяРабота.поисковВладельца == первыеЗадания.count)
        #expect(перваяРабота.поисковРасстояния == первыеЗадания.count)
        #expect(перваяРабота.полученийНабораХэшей == первыеЗадания.count)
        #expect(перваяРабота.проверокНаличияХэша == первыеЗадания.count)
        #expect(перваяРабота.сравненийСортировки > 0)

        #expect(втораяРабота.построенныхУзловИндекса == второйРазмер)
        #expect(втораяРабота.построенныхХэшейИндекса == второйРазмер - 1)
        #expect(втораяРабота.построенныхСвязейИндекса == второйРазмер - 1)
        #expect(втораяРабота.посещённыхВершин == второйРазмер)
        #expect(втораяРабота.просмотренныхРёбер == 2 * (второйРазмер - 1))
        #expect(втораяРабота.подготовкаИндекса == 6 * второйРазмер - 4)
        #expect(втораяРабота.подготовкаИндекса == 2 * перваяРабота.подготовкаИндекса + 4)
        #expect(втораяРабота.поисковВладельца == вторыеЗадания.count)
        #expect(втораяРабота.поисковРасстояния == вторыеЗадания.count)
        #expect(втораяРабота.полученийНабораХэшей == вторыеЗадания.count)
        #expect(втораяРабота.проверокНаличияХэша == вторыеЗадания.count)
        #expect(втораяРабота.сравненийСортировки > 0)
    }

    private func создатьКаталогСУзлами(
        числоУзлов: Int
    ) throws -> (каталог: КаталогЛокальныхАдресов, исходныйАдрес: АдресЛокальногоУзла) {
        let корень = try адрес("fum")
        let узлы = try (1..<числоУзлов).map { номерУзла in
            (
                try АдресЛокальногоУзла(["fum", "узел-\(номерУзла)"]),
                "владелец-\(номерУзла)",
                "узлы/\(номерУзла).json",
                хэш("a")
            )
        }
        return (
            try создатьКаталог(корень: корень, владелецКорня: "владелец-корня", узлы: узлы),
            корень)
    }

    private func создатьЗадания(для каталог: КаталогЛокальныхАдресов) -> [ЗаданиеЛокальнойОчереди] {
        каталог.узлы.filter { $0.адрес != каталог.корень }.enumerated().map { номер, узел in
            задание(
                "задание-\(номер)",
                узел.адрес,
                узел.владелец,
                узел.хэшиДоступныхДанных,
                0)
        }
    }

    private func адрес(_ компоненты: String...) throws -> АдресЛокальногоУзла {
        try АдресЛокальногоУзла(компоненты)
    }

    private func хэш(_ символ: Character) -> String {
        String(repeating: String(символ), count: 64)
    }

    private func задание(
        _ идентификатор: String,
        _ адрес: АдресЛокальногоУзла,
        _ владелец: String,
        _ хэши: [String],
        _ стоимостьПередачиБайт: UInt64
    ) -> ЗаданиеЛокальнойОчереди {
        ЗаданиеЛокальнойОчереди(
            идентификатор: идентификатор,
            адрес: адрес,
            владелец: владелец,
            требуемыеХэшиДанных: хэши,
            стоимостьПередачиБайт: стоимостьПередачиБайт)
    }

    private func создатьКаталог(
        корень: АдресЛокальногоУзла,
        владелецКорня: String,
        узлы: [(АдресЛокальногоУзла, String, String, String)],
        связи: [СвязьСотрудничества] = []
    ) throws -> КаталогЛокальныхАдресов {
        let наблюдение = try создатьПроекцию(узлы.map { ($0.2, "файл", $0.3) })
        let привязки = узлы.map {
            ПривязкаАдресаКФайлу(адрес: $0.0, относительныйПуть: $0.2, владелец: $0.1)
        }
        return try КаталогЛокальныхАдресов(
            наблюдение: наблюдение,
            корень: корень,
            владелецКорня: владелецКорня,
            привязки: привязки,
            связиСотрудничества: связи)
    }

    private func создатьПроекцию(
        _ файлы: [(String, String, String)]
    ) throws -> ПроекцияФайловойСистемы {
        ПроекцияФайловойСистемы(
            физическийКорень: "/fixture-root",
            источник: "synthetic-locality-fixture",
            предшественник: nil,
            идентификатор: хэш("f"),
            записи: файлы.map { путь, тип, хэш in
                ПроекцияЗаписиФайловойСистемы(
                    путь: путь,
                    тип: тип,
                    владелец: 501,
                    режим: 0o600,
                    размер: 0,
                    цельСсылки: nil,
                    хэш: хэш)
            })
    }

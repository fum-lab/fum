    @Test("Общий родитель сравнивается после одинакового расстояния графа")
    func общийРодитель() throws {
        let корень = try адрес("fum")
        let источник = try адрес("fum", "team", "origin")
        let ближнийРодитель = try адрес("fum", "team", "peer")
        let другойРодитель = try адрес("fum", "other", "peer")
        let связи = [try СвязьСотрудничества(источник, ближнийРодитель), try СвязьСотрудничества(источник, другойРодитель)]
        let каталог = try создатьКаталог(
            корень: корень,
            владелецКорня: "coordinator",
            узлы: [
                (try адрес("fum", "team"), "owner-team", "team.json", хэш("e")),
                (источник, "owner-origin", "origin.json", хэш("b")),
                (ближнийРодитель, "owner-close", "close.json", хэш("c")),
                (try адрес("fum", "other"), "owner-other-root", "other-parent.json", хэш("f")),
                (другойРодитель, "owner-other", "other.json", хэш("d"))
            ],
            связи: связи)

        let план = try РаспределительЛокальнойОчереди.упорядочить([
            задание("other", другойРодитель, "owner-other", [], 0),

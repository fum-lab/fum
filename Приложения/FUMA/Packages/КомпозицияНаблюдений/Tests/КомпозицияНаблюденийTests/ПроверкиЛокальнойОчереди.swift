    func сначалаДанные() throws {
        let корень = try адрес("fum")
        let источник = try адрес("fum", "near", "origin")
        let ближний = try адрес("fum", "near", "child")
        let дальний = try адрес("fum", "far", "child")
        let нужныйХэш = хэш("a")
        let каталог = try создатьКаталог(
            корень: корень,
            владелецКорня: "coordinator",
            узлы: [
                (try адрес("fum", "near"), "owner-near", "near.json", хэш("e")),
                (источник, "owner-origin", "origin.json", хэш("b")),
                (ближний, "owner-close", "close.json", хэш("c")),
                (try адрес("fum", "far"), "owner-far-root", "far-parent.json", хэш("d")),
                (дальний, "owner-far", "far.json", нужныйХэш)
            ])
        let задания = [
            задание("close", ближний, "owner-close", [хэш("d")], 0),
            задание("far", дальний, "owner-far", [нужныйХэш], 900_000)
        ]

        let план = try РаспределительЛокальнойОчереди.упорядочить(задания, из: источник, по: каталог)

        #expect(план.порядок.map(\.задание.идентификатор) == ["far", "close"])
        #expect(план.порядок[0].доступноТребуемыхДанных == 1)
    }


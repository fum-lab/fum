import Foundation
import Darwin
import Testing
import КонтейнерНаблюдений
@testable import КомпозицияНаблюдений

@Suite("Цикл ввода JSONL")
struct ПроверкиЦиклаВводаJSONL {
    @Test("Точные байты и границы после закрытия")
    func точнаяЗапись() throws {
        let история = try временнаяИсторияВвода()
        let данные = Data("один\r\n\nхвост".utf8)
        let цикл = ЦиклВводаJSONL()
        let первый = try записанныйПакет(цикл.принять(
            данные, источник: "синтетический", поколение: "1", после: nil, история: история))
        let прочитан = try цикл.прочитать(первый.идентификатор, история: история)
        #expect(прочитан.сырыеНовыеБайты == данные)
        try #require(прочитан.рамки.count == 2)
        #expect(прочитан.рамки[0].начало == 0)
        #expect(прочитан.рамки[1].конец == Data("один\r\n\n".utf8).count)
        #expect(прочитан.началоХвоста == Data("один\r\n\n".utf8).count)
        #expect(прочитан.конец == данные.count)
        #expect(try цикл.восстановить(первый.идентификатор, история: история) == данные)
    }

    @Test("Повтор и одинаковые строки на разных смещениях")
    func повторИРазныеСмещения() throws {
        let история = try временнаяИсторияВвода()
        let цикл = ЦиклВводаJSONL()
        let строка = Data("x\n".utf8)
        let первый = try записанныйПакет(цикл.принять(
            строка, источник: "источник", поколение: "1", после: nil, история: история))
        let повтор = try цикл.принять(
            строка, источник: "источник", поколение: "1", после: первый.идентификатор, история: история)
        guard case .повтор(let прежний) = повтор else { Issue.record("Ожидался повтор"); return }
        #expect(прежний == первый.идентификатор)
        #expect(try цикл.числоПакетов(история: история) == 1)
        let второй = try записанныйПакет(цикл.принять(
            строка + строка, источник: "источник", поколение: "1", после: первый.идентификатор, история: история))
        let пакет = try цикл.прочитать(второй.идентификатор, история: история)
        #expect(пакет.сырыеНовыеБайты == строка)
        try #require(пакет.рамки.count == 1)
        #expect(пакет.рамки[0].начало == строка.count)
        #expect(пакет.рамки[0].конец == строка.count * 2)
        #expect(пакет.сохраненоСырыхБайтов == строка.count * 2)
        #expect(try цикл.восстановить(второй.идентификатор, история: история) == строка + строка)
    }

    @Test("Хвост завершается после нескольких открытий")
    func завершениеХвоста() throws {
        let история = try временнаяИсторияВвода()
        let цикл = ЦиклВводаJSONL()
        let первый = try записанныйПакет(цикл.принять(
            Data("a".utf8), источник: "источник", поколение: "1", после: nil, история: история))
        let второй = try записанныйПакет(цикл.принять(
            Data("ab".utf8), источник: "источник", поколение: "1", после: первый.идентификатор, история: история))
        let третий = try записанныйПакет(цикл.принять(
            Data("ab\n".utf8), источник: "источник", поколение: "1", после: второй.идентификатор, история: история))
        let пакет = try цикл.прочитать(третий.идентификатор, история: история)
        #expect(пакет.сырыеНовыеБайты == Data("\n".utf8))
        try #require(пакет.рамки.count == 1)
        #expect(пакет.рамки[0].начало == 0 && пакет.рамки[0].конец == 3)
        #expect(пакет.началоХвоста == 3 && пакет.конец == 3)
        #expect(пакет.сохраненоСырыхБайтов == 3)
        #expect(пакет.провереноБайтовСканерами == 9)
        #expect(try цикл.восстановить(третий.идентификатор, история: история) == Data("ab\n".utf8))
    }

    @Test("Смена поколения, дрейф и бюджет не записывают вход")
    func дрейфИПредел() throws {
        let история = try временнаяИсторияВвода()
        let цикл = ЦиклВводаJSONL(пределБайтов: 8)
        let первый = try записанныйПакет(цикл.принять(
            Data("a\nх".utf8), источник: "источник", поколение: "1", после: nil, история: история))
        let смена = try цикл.принять(
            Data("a\nх".utf8), источник: "источник", поколение: "2", после: первый.идентификатор, история: история)
        guard case .сменаИсточника = смена else { Issue.record("Ожидалась смена источника"); return }
        let сменаИмени = try цикл.принять(
            Data("a\nх".utf8), источник: "другой", поколение: "1", после: первый.идентификатор, история: история)
        guard case .сменаИсточника = сменаИмени else { Issue.record("Ожидалась смена имени источника"); return }
        let дрейф = try цикл.принять(
            Data("b\nх".utf8), источник: "источник", поколение: "1", после: первый.идентификатор, история: история)
        guard case .дрейф = дрейф else { Issue.record("Ожидался дрейф"); return }
        let дрейфХвоста = try цикл.принять(
            Data("a\nу".utf8), источник: "источник", поколение: "1", после: первый.идентификатор, история: история)
        guard case .дрейф = дрейфХвоста else { Issue.record("Ожидался дрейф хвоста"); return }
        let усечение = try цикл.принять(
            Data("a\n".utf8), источник: "источник", поколение: "1", после: первый.идентификатор, история: история)
        guard case .дрейф = усечение else { Issue.record("Ожидалось усечение"); return }
        let предел = try цикл.принять(
            Data(repeating: 65, count: 9), источник: "источник", поколение: "1", после: первый.идентификатор, история: история)
        guard case .предел = предел else { Issue.record("Ожидался предел"); return }
        #expect(try цикл.числоПакетов(история: история) == 1)
        let операции = ФайловыеОперации(
            запись: ФайловыеОперации.системные.запись,
            синхронизация: { _ in throw ОшибкаПроверкиВвода.сбойСинхронизации })
        let неизвестно = try цикл.принять(
            Data("a\nх\n".utf8), источник: "источник", поколение: "1",
            после: первый.идентификатор, история: история, операции: операции)
        guard case .неизвестныйИсход(let идентификатор, let хэш, let диагностика) = неизвестно,
              let идентификатор, let хэш else { Issue.record("Ожидался неизвестный исход с привязкой"); return }
        print("Неизвестный исход: история=\(история.path), идентификатор=\(идентификатор), sha256=\(хэш), стадия=\(диагностика.стадия), причина=\(диагностика.причина)")
        #expect(диагностика.стадия == .добавление)
        #expect(диагностика.причина == .другая)
        #expect(try цикл.подтвердить(идентификатор, sha256Пакета: хэш, история: история))
        #expect(try цикл.прочитать(идентификатор, история: история).сырыеНовыеБайты == Data("\n".utf8))
    }
}

private enum ОшибкаПроверкиВвода: Error {
    case нетПакета(ИсходВводаJSONL), сбойСинхронизации, невозможноРазрешить(Int32), путьИзменён
}

private func записанныйПакет(_ исход: ИсходВводаJSONL) throws -> СсылкаПакетаВводаJSONL {
    guard case .записано(let ссылка) = исход else { throw ОшибкаПроверкиВвода.нетПакета(исход) }
    return ссылка
}

private func временнаяИсторияВвода() throws -> URL {
    let адрес: URL
    if let путь = ProcessInfo.processInfo.environment["ФУМА_ДИАГНОСТИЧЕСКАЯ_ИСТОРИЯ"] {
        let родитель = URL(fileURLWithPath: путь, isDirectory: true)
        адрес = родитель.appendingPathComponent("fuma-case-" + UUID().uuidString, isDirectory: true)
    } else {
        адрес = FileManager.default.temporaryDirectory.appendingPathComponent(
            "fuma-vvod-jsonl-" + UUID().uuidString, isDirectory: true)
    }
    try FileManager.default.createDirectory(
        at: адрес, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
    guard let указатель = realpath(адрес.path, nil) else {
        throw ОшибкаПроверкиВвода.невозможноРазрешить(errno)
    }
    defer { free(указатель) }
    let путь = String(cString: указатель)
    let физический = URL(fileURLWithPath: путь, isDirectory: true)
    guard физический.path == путь else { throw ОшибкаПроверкиВвода.путьИзменён }
    print("Приватная синтетическая история: \(физический.path)")
    return физический
}

import Foundation
import Testing
@testable import КомпозицияНаблюдений

@Suite("Композиция read-only наблюдений")
struct ПроверкиКомпозицииНаблюдений {
    @Test("План сохраняет порядок, раздельные корни и отрицание общей атомарности")
    func границыПлана() async throws {
        let поставщик = ПроверочныйПоставщикНаблюдений()
        let компоновщик = КомпоновщикНаблюденийСостояния(поставщик: поставщик)
        let кореньФайловойСистемы = URL(fileURLWithPath: "/private/tmp/наблюдаемая-файловая-система")
        let кореньРепозитория = URL(fileURLWithPath: "/private/tmp/наблюдаемый-репозиторий")

        let план = try await компоновщик.построить(
            кореньФайловойСистемы: кореньФайловойСистемы,
            источникФайловойСистемы: "проверочный-источник",
            кореньРепозитория: кореньРепозитория)

        #expect(await поставщик.порядокВызовов() == [.файловаяСистема, .репозиторий])
        #expect(план.порядок == [.файловаяСистема, .репозиторий])
        #expect(!план.атомарностьМеждуНаблюдениямиГарантирована)
        #expect(план.файловаяСистема.физическийКорень == кореньФайловойСистемы.path)
        #expect(план.репозиторий.физическийКорень == кореньРепозитория.path)
    }

    @Test("Канонические байты повторяются и заканчиваются LF")
    func каноническиеБайты() async throws {
        let поставщик = ПроверочныйПоставщикНаблюдений()
        let план = try await КомпоновщикНаблюденийСостояния(поставщик: поставщик).построить(
            кореньФайловойСистемы: URL(fileURLWithPath: "/private/tmp/наблюдаемая-файловая-система"),
            источникФайловойСистемы: "проверочный-источник",
            кореньРепозитория: URL(fileURLWithPath: "/private/tmp/наблюдаемый-репозиторий"))

        let первыеБайты = try план.каноническиеБайты()
        let вторыеБайты = try план.каноническиеБайты()
        #expect(первыеБайты == вторыеБайты)
        #expect(первыеБайты.last == 0x0a)
        #expect(try JSONDecoder().decode(ПланНаблюденийСостояния.self, from: первыеБайты) == план)
    }

    @Test("Декодирование отвергает чужую схему, порядок и обещание атомарности")
    func отказОтОслабленногоКонтракта() async throws {
        let поставщик = ПроверочныйПоставщикНаблюдений()
        let план = try await КомпоновщикНаблюденийСостояния(поставщик: поставщик).построить(
            кореньФайловойСистемы: URL(fileURLWithPath: "/private/tmp/наблюдаемая-файловая-система"),
            источникФайловойСистемы: "проверочный-источник",
            кореньРепозитория: URL(fileURLWithPath: "/private/tmp/наблюдаемый-репозиторий"))
        let исходныйТекст = String(decoding: try план.каноническиеБайты(), as: UTF8.self)
        let ослабленныеТексты = [
            исходныйТекст.replacingOccurrences(
                of: "fuma.план-наблюдений-файловой-системы-и-репозитория.1",
                with: "чужая-схема"),
            исходныйТекст.replacingOccurrences(
                of: "\"файловая-система\"",
                with: "\"репозиторий\""),
            исходныйТекст.replacingOccurrences(of: " : false", with: " : true")
        ]

        for текст in ослабленныеТексты {
            #expect(throws: DecodingError.self) {
                try JSONDecoder().decode(ПланНаблюденийСостояния.self, from: Data(текст.utf8))
            }
        }
    }

    @Test("Ошибка второго наблюдения не создаёт план и не вызывает повтор")
    func отказБезПовтора() async {
        let поставщик = ПроверочныйПоставщикНаблюдений(отказатьНаРепозитории: true)
        let компоновщик = КомпоновщикНаблюденийСостояния(поставщик: поставщик)

        await #expect(throws: ПроверочнаяОшибка.репозиторий) {
            try await компоновщик.построить(
                кореньФайловойСистемы: URL(fileURLWithPath: "/private/tmp/наблюдаемая-файловая-система"),
                источникФайловойСистемы: "проверочный-источник",
                кореньРепозитория: URL(fileURLWithPath: "/private/tmp/наблюдаемый-репозиторий"))
        }
        #expect(await поставщик.порядокВызовов() == [.файловаяСистема, .репозиторий])
    }
}

private actor ПроверочныйПоставщикНаблюдений: ПоставщикНаблюденийСостояния {
    private let отказатьНаРепозитории: Bool
    private var вызовы: [ШагНаблюденияСостояния] = []

    init(отказатьНаРепозитории: Bool = false) {
        self.отказатьНаРепозитории = отказатьНаРепозитории
    }

    func наблюдатьФайловуюСистему(
        корень: URL,
        источник: String
    ) async throws -> ПроекцияФайловойСистемы {
        вызовы.append(.файловаяСистема)
        return ПроекцияФайловойСистемы(
            физическийКорень: корень.path,
            источник: источник,
            предшественник: nil,
            идентификатор: String(repeating: "a", count: 64),
            записи: [
                ПроекцияЗаписиФайловойСистемы(
                    путь: "пример",
                    тип: "файл",
                    владелец: 501,
                    режим: 0o600,
                    размер: 3,
                    цельСсылки: nil,
                    хэш: String(repeating: "b", count: 64))
            ])
    }

    func наблюдатьРепозиторий(корень: URL) async throws -> ПроекцияРепозитория {
        вызовы.append(.репозиторий)
        if отказатьНаРепозитории {
            throw ПроверочнаяОшибка.репозиторий
        }
        return ПроекцияРепозитория(
            схема: "fuma.снимок-репозитория.1",
            физическийКорень: корень.path,
            коммит: String(repeating: "c", count: 40),
            ссылка: "refs/heads/codex/проверка",
            изменённыеПути: [],
            неотслеживаемыеПути: [])
    }

    func порядокВызовов() -> [ШагНаблюденияСостояния] {
        вызовы
    }
}

private enum ПроверочнаяОшибка: Error, Equatable {
    case репозиторий
}

    }
}

public struct ПланНаблюденийСостояния: Codable, Equatable, Sendable {
    private static let ожидаемаяСхема = "fuma.план-наблюдений-файловой-системы-и-репозитория.1"
    private static let ожидаемыйПорядок: [ШагНаблюденияСостояния] = [.файловаяСистема, .репозиторий]

    public let схема: String
    public let порядок: [ШагНаблюденияСостояния]
    public let атомарностьМеждуНаблюдениямиГарантирована: Bool
    public let файловаяСистема: ПроекцияФайловойСистемы
    public let репозиторий: ПроекцияРепозитория

    public init(
        файловаяСистема: ПроекцияФайловойСистемы,
        репозиторий: ПроекцияРепозитория
    ) {
        self.схема = Self.ожидаемаяСхема
        self.порядок = Self.ожидаемыйПорядок
        self.атомарностьМеждуНаблюдениямиГарантирована = false
        self.файловаяСистема = ПроекцияФайловойСистемы(
            физическийКорень: файловаяСистема.физическийКорень,
            источник: файловаяСистема.источник,
            предшественник: файловаяСистема.предшественник,
            идентификатор: файловаяСистема.идентификатор,
            записи: файловаяСистема.записи)
        self.репозиторий = ПроекцияРепозитория(
            схема: репозиторий.схема,
            физическийКорень: репозиторий.физическийКорень,
            коммит: репозиторий.коммит,
            ссылка: репозиторий.ссылка,
            изменённыеПути: репозиторий.изменённыеПути,
            неотслеживаемыеПути: репозиторий.неотслеживаемыеПути)
    }

    public init(from decoder: Decoder) throws {
        let контейнер = try decoder.container(keyedBy: CodingKeys.self)
        let схема = try контейнер.decode(String.self, forKey: .схема)
        guard схема == Self.ожидаемаяСхема else {
            throw DecodingError.dataCorruptedError(
                forKey: .схема,
                in: контейнер,
                debugDescription: "Неизвестная схема плана наблюдений")
        }
        let порядок = try контейнер.decode([ШагНаблюденияСостояния].self, forKey: .порядок)
        guard порядок == Self.ожидаемыйПорядок else {
            throw DecodingError.dataCorruptedError(
                forKey: .порядок,
                in: контейнер,
                debugDescription: "Порядок наблюдений не совпадает с контрактом")
        }
        let атомарность = try контейнер.decode(Bool.self, forKey: .атомарностьМеждуНаблюдениямиГарантирована)
        guard !атомарность else {
            throw DecodingError.dataCorruptedError(
                forKey: .атомарностьМеждуНаблюдениямиГарантирована,
                in: контейнер,
                debugDescription: "Общая атомарность наблюдений не гарантируется")
        }
        let файловаяСистема = try контейнер.decode(ПроекцияФайловойСистемы.self, forKey: .файловаяСистема)
        let репозиторий = try контейнер.decode(ПроекцияРепозитория.self, forKey: .репозиторий)
        let нормализованный = Self(файловаяСистема: файловаяСистема, репозиторий: репозиторий)
        guard нормализованный.файловаяСистема == файловаяСистема,
              нормализованный.репозиторий == репозиторий else {
            throw DecodingError.dataCorruptedError(
                forKey: .файловаяСистема,
                in: контейнер,
                debugDescription: "Пути наблюдений не упорядочены")
        }
        self = нормализованный
    }

    public func каноническиеБайты() throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(self) + Data([0x0a])
    }

    private enum CodingKeys: String, CodingKey {
        case схема
        case порядок
        case атомарностьМеждуНаблюдениямиГарантирована
        case файловаяСистема
        case репозиторий
    }
}

public protocol ПоставщикНаблюденийСостояния: Sendable {
    func наблюдатьФайловуюСистему(корень: URL, источник: String) async throws -> ПроекцияФайловойСистемы
    func наблюдатьРепозиторий(корень: URL) async throws -> ПроекцияРепозитория
}

public struct СистемныйПоставщикНаблюденийСостояния: ПоставщикНаблюденийСостояния {
    public init() {}

    public func наблюдатьФайловуюСистему(
        корень: URL,
        источник: String
    ) async throws -> ПроекцияФайловойСистемы {
        let снимок = try НаблюдениеФайловойСистемы.наблюдать(корень: корень, источник: источник)
        return ПроекцияФайловойСистемы(
            физическийКорень: корень.path,
            источник: снимок.источник,
            предшественник: снимок.предшественник,
            идентификатор: снимок.идентификатор,
            записи: снимок.записи.map {
                ПроекцияЗаписиФайловойСистемы(
                    путь: $0.путь,
                    тип: $0.тип.rawValue,
                    владелец: $0.владелец,
                    режим: $0.режим,
                    размер: $0.размер,
                    цельСсылки: $0.цельСсылки,
                    хэш: $0.хэш)
            })
    }

    public func наблюдатьРепозиторий(корень: URL) async throws -> ПроекцияРепозитория {
        let снимок = try НаблюдательРепозитория.наблюдать(корень: корень)
        return ПроекцияРепозитория(
            схема: снимок.схема,
            физическийКорень: снимок.корень,
            коммит: снимок.коммит,
            ссылка: снимок.ссылка,
            изменённыеПути: снимок.изменённыеПути,
            неотслеживаемыеПути: снимок.неотслеживаемыеПути)
    }
}

public struct КомпоновщикНаблюденийСостояния<Поставщик: ПоставщикНаблюденийСостояния>: Sendable {
    private let поставщик: Поставщик

    public init(поставщик: Поставщик) {
        self.поставщик = поставщик
    }

    public func построить(
        кореньФайловойСистемы: URL,
        источникФайловойСистемы: String,
        кореньРепозитория: URL
    ) async throws -> ПланНаблюденийСостояния {
        let файловаяСистема = try await поставщик.наблюдатьФайловуюСистему(
            корень: кореньФайловойСистемы,
            источник: источникФайловойСистемы)
        let репозиторий = try await поставщик.наблюдатьРепозиторий(корень: кореньРепозитория)
        return ПланНаблюденийСостояния(
            файловаяСистема: файловаяСистема,
            репозиторий: репозиторий)
    }
}

public extension КомпоновщикНаблюденийСостояния where Поставщик == СистемныйПоставщикНаблюденийСостояния {
    init() {
        self.init(поставщик: СистемныйПоставщикНаблюденийСостояния())
    }
}

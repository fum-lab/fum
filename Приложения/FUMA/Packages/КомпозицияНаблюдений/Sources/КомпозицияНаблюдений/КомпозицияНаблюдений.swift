import Foundation
import КонтейнерНаблюдений
import НаблюдательРепозитория

public enum ШагНаблюденияСостояния: String, Codable, Equatable, Sendable {
    case файловаяСистема = "файловая-система"
    case репозиторий
}

public struct ПроекцияЗаписиФайловойСистемы: Codable, Equatable, Sendable {
    public let путь: String
    public let тип: String
    public let владелец: UInt32
    public let режим: UInt16
    public let размер: UInt64
    public let цельСсылки: String?
    public let хэш: String

    public init(
        путь: String,
        тип: String,
        владелец: UInt32,
        режим: UInt16,
        размер: UInt64,
        цельСсылки: String?,
        хэш: String
    ) {
        self.путь = путь
        self.тип = тип
        self.владелец = владелец
        self.режим = режим
        self.размер = размер
        self.цельСсылки = цельСсылки
        self.хэш = хэш
    }
}

public struct ПроекцияФайловойСистемы: Codable, Equatable, Sendable {
    public let физическийКорень: String
    public let источник: String
    public let предшественник: String?
    public let идентификатор: String
    public let записи: [ПроекцияЗаписиФайловойСистемы]

    public init(
        физическийКорень: String,
        источник: String,
        предшественник: String?,
        идентификатор: String,
        записи: [ПроекцияЗаписиФайловойСистемы]
    ) {
        self.физическийКорень = физическийКорень
        self.источник = источник
        self.предшественник = предшественник
        self.идентификатор = идентификатор
        self.записи = записи.sorted { $0.путь.utf8.lexicographicallyPrecedes($1.путь.utf8) }
    }
}


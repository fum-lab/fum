/// КонтейнерНаблюдений.НаблюдениеФайловойСистемы видит верхний уровень временного
/// корня, не рекурсивные каталоги клетки; он не подключается к этому bounded port.
/// Явная идентичность клетки; полный ref не ограничен префиксом codex/.
public struct НазначениеКорневойКлетки: Codable, Equatable, Sendable {

    case неверныйКонтекстРедуктора
}

/// Возвращает продолжение вызывающей стороне; общий runtime здесь не запускается.
public struct НормализаторКорнейКлетки<Порт: ПортСведенияКорнейКлетки>: Sendable {
    private var порт: Порт
    public init(порт: Порт) { self.порт = порт }
    public var состояниеПорта: Порт { порт }

    public mutating func выполнить(назначение: НазначениеКорневойКлетки,
                                    отображение: ОтображениеКорнейКлетки,
                                    политика: ПолитикаСведенияКорней,
                                    контекст: КонтекстКомандыКлетки,
                                    редуктор: inout Редуктор) throws -> ИсходСведенияКлетки {
        guard допустимо(назначение, отображение),
              контекст.задача == редуктор.снимок.задача,
              допустимыйИДОперации(контекст.операция),
              контекст.область == КонтекстКомандыКлетки.областьДля(назначение, отображение, политика),
              контекст.область.utf8.count <= 1024,
              контекст.первыйТакт >= 0, контекст.первыйТакт <= Int64.max - 3,
              контекст.источникКоманды.канал == .команда,
              контекст.источникНаблюдения.канал == .интерфейс else {
            throw ОшибкаСведенияКлетки.неверноеНазначениеИлиОтображение
        }

        let до: НаблюдениеКорнейКлетки
        do { до = try порт.наблюдать(назначение, отображение: отображение) }
        catch { return .неизвестен(причина: "наблюдение-обоих-корней-недоступно", наблюдение: nil) }
        guard до.полныйОхват else {
            return .неизвестен(причина: "порт-не-подтвердил-полный-охват", наблюдение: до)
        }
        let сохранённое: НамерениеСведенияКорней?
        do { сохранённое = try порт.прочитатьНамерение(операция: контекст.операция) }
        catch { return .неизвестен(причина: "чтение-durable-intent-недоступно", наблюдение: до) }
        let операция = редуктор.снимок.операции.first { $0.идентификатор == контекст.операция }

        if до.исходныйКорень == nil {
            guard let цель = до.целевойКорень,
                  цель.назначение == назначение, цель.имяКорня == отображение.целевоеИмя else {
                return .конфликт(причина: "целевой-корень-отсутствует-или-чужой", наблюдение: до)
            }
            guard цель.полныйОхват, допустимСостав(цель) else {
                return .неизвестен(причина: "целевая-клетка-неполностью-наблюдаема", наблюдение: до)
            }
            guard провереноВладение(цель, назначение) else {
                return .неизвестен(причина: "владелец-целевой-клетки-не-подтверждён", наблюдение: до)
            }
            guard let намерение = сохранённое else {
                guard операция == nil else {
                    return .неизвестен(причина: "нет-pinned-intent-для-завершения-операции", наблюдение: до)
                }
                return .безИзменений(.init(назначение: назначение, отображение: отображение,
                    идентификаторНамерения: nil, отпечатокЦелевогоКорня: отпечаток(цель), целевойСнимок: цель))
            }
            guard проверитьНамерение(намерение, операция: контекст.операция,
                                      назначение: назначение, отображение: отображение, политика: политика),
                  совпадаетЦель(цель, intent: намерение),
                  до.целевойКорень != nil else {
                return .конфликт(причина: "цель-не-совпадает-с-двумя-pinned-входами", наблюдение: до)
            }
            guard до.исходныйКорень == nil,
                  let операция,
                  операция.ожидаемыйЭффект == текстЭффекта(намерение) else {
                return .неизвестен(причина: "сведённая-цель-без-согласованного-reducer-намерения", наблюдение: до)
            }
            if операция.подтверждение == nil {
                try проверитьДополнениеРедуктора(контекст, намерение: намерение,
                                                  подтверждение: true, редуктор: редуктор)
                try записатьПодтверждение(контекст, намерение: намерение, наблюдение: до,
                                          цель: цель, редуктор: &редуктор)
                return .сведено(продолжение(намерение, цель))
            }
            return .безИзменений(продолжение(намерение, цель))
        }

        guard let источник = до.исходныйКорень,
              источник.назначение == назначение, источник.имяКорня == отображение.исходноеИмя else {
            return .конфликт(причина: "исходный-корень-непринадлежит-назначению", наблюдение: до)
        }
        guard источник.полныйОхват, допустимСостав(источник) else {
            return .неизвестен(причина: "исходная-клетка-неполностью-наблюдаема", наблюдение: до)
        }
        if let цель = до.целевойКорень,
           цель.назначение != назначение || цель.имяКорня != отображение.целевоеИмя {
            return .конфликт(причина: "цель-принадлежит-другому-владельцу-или-ref", наблюдение: до)
        }
        if let цель = до.целевойКорень {
            guard цель.полныйОхват, допустимСостав(цель) else {
                return .неизвестен(причина: "целевая-клетка-неполностью-наблюдаема", наблюдение: до)
            }
        }

        guard let слияние = построитьОжидаемыеЗаписи(источник: источник, цель: до.целевойКорень,
                                                       политика: политика) else {
            guard операция == nil, сохранённое == nil else {
                return .неизвестен(причина: "предыдущий-intent-имеет-неразрешённую-коллизию; исход-эффекта-не-установлен", наблюдение: до)
            }
            return .нерешённаяКоллизия(пути: путиКоллизий(источник: источник, цель: до.целевойКорень),
                                       наблюдение: до)
        }
        guard провереноВладение(источник, назначение),
              до.целевойКорень.map({ провереноВладение($0, назначение) }) ?? true else {
            return .неизвестен(причина: "порт-не-подтвердил-владение-обоими-корнями", наблюдение: до)
        }
        if let операция {
            guard операция.подтверждение == nil, let намерение = сохранённое,
                  проверитьНамерение(намерение, операция: контекст.операция,
                                     назначение: назначение, отображение: отображение, политика: политика),
                  намерение.ожидаемыйИсходныйКорень == источник,
                  намерение.ожидаемыйЦелевойКорень == до.целевойКорень else {
                return .неизвестен(причина: "прошлая-команда-не-завершена; повтор-эффекта-запрещён", наблюдение: до)
            }
            return .неизвестен(причина: "оба-исходных-корня-ещё-на-месте-после-команды", наблюдение: до)
        }

        let intent = сохранённое ?? построитьНамерение(
            операция: контекст.операция, назначение: назначение, отображение: отображение,
            политика: политика, источник: источник, цель: до.целевойКорень, ожидаемаяЦель: слияние)
        guard проверитьНамерение(intent, операция: контекст.операция, назначение: назначение,
                                  отображение: отображение, политика: политика),
              intent.ожидаемыйИсходныйКорень == источник,
              intent.ожидаемыйЦелевойКорень == до.целевойКорень else {
            return .конфликт(причина: "durable-intent-не-связан-с-текущим-двойным-снимком", наблюдение: до)
        }
        try проверитьДополнениеРедуктора(контекст, намерение: intent,
                                          подтверждение: false, редуктор: редуктор)
        if сохранённое == nil {
            do {
                try порт.сохранитьНамерение(intent)
                guard try порт.прочитатьНамерение(операция: контекст.операция) == intent else {
                    return .неизвестен(причина: "durable-intent-readback-не-совпал", наблюдение: до)
                }
            } catch {
                return .неизвестен(причина: "durable-intent-сохранение-не-имеет-известного-исхода", наблюдение: до)
            }
        }
        try принятьКоманду(контекст, намерение: intent, фаза: .намерение,
                           такт: контекст.первыйТакт, редуктор: &редуктор)
        try принятьКоманду(контекст, намерение: intent, фаза: .отправлена,
                           такт: контекст.первыйТакт + 1, редуктор: &редуктор)
        do {
            let результат = try порт.свестиКорни(intent)
            if case let .обнаруженыРазличающиесяЗаписи(пути) = результат {
                let после = try? порт.наблюдать(назначение, отображение: отображение)
                guard let после, после.полныйОхват,
                      после.исходныйКорень == intent.ожидаемыйИсходныйКорень,
                      после.целевойКорень == intent.ожидаемыйЦелевойКорень else {
                    return .неизвестен(причина: "порт-сообщил-коллизию-но-оба-корня-не-подтверждены", наблюдение: после)
                }
                return .нерешённаяКоллизия(пути: пути, наблюдение: после)
            }
        } catch {
            // Ошибка после начала apply не доказывает отсутствия эффекта.
        }
        let после = try? порт.наблюдать(назначение, отображение: отображение)
        guard let после, после.полныйОхват, после.исходныйКорень == nil,
              let цель = после.целевойКорень,
              совпадаетЦель(цель, intent: intent) else {
            return .неизвестен(причина: "после-эффекта-неподтверждённый-двойной-readback", наблюдение: после)
        }
        let pinnedAfter: НамерениеСведенияКорней?
        do { pinnedAfter = try порт.прочитатьНамерение(операция: контекст.операция) }
        catch { return .неизвестен(причина: "после-эффекта-durable-intent-недоступен", наблюдение: после) }
        guard pinnedAfter == intent else {
            return .неизвестен(причина: "после-эффекта-durable-intent-изменился", наблюдение: после)
        }
        try записатьПодтверждение(контекст, намерение: intent, наблюдение: после,
                                  цель: цель, редуктор: &редуктор)
        return .сведено(продолжение(intent, цель))
    }
}

private func допустимо(_ назначение: НазначениеКорневойКлетки,
                       _ отображение: ОтображениеКорнейКлетки) -> Bool {
    func имя(_ s: String) -> Bool {
        !s.isEmpty && s != "." && s != ".." && !s.contains("/") && !s.contains("\\")
            && s.utf8.count <= 128 && s.caseInsensitiveCompare(".git") != .orderedSame
            && !s.unicodeScalars.contains { $0.value == 0 || $0.value < 32 || $0.value == 127 }
    }
    let refParts = назначение.ветка.split(separator: "/", omittingEmptySubsequences: false)
    let forbidden: Set<Unicode.Scalar> = ["~", "^", ":", "?", "*", "[", "\\", " "]
    func идентификатор(_ s: String) -> Bool {
        !s.isEmpty && s.utf8.count <= 64
            && !s.unicodeScalars.contains { $0.value < 32 || $0.value == 127 }
    }
    return идентификатор(назначение.идентификаторКлетки) && идентификатор(назначение.владелец)
        && назначение.ветка.hasPrefix("refs/heads/") && назначение.ветка.utf8.count <= 256
        && !назначение.ветка.hasSuffix("/") && !назначение.ветка.contains("//")
        && !назначение.ветка.contains("..") && !назначение.ветка.contains("@{")
        && refParts.allSatisfy { !$0.isEmpty && $0 != "." && $0 != ".." && !$0.hasPrefix(".")
            && !$0.hasSuffix(".") && !$0.hasSuffix(".lock") }
        && назначение.ветка.unicodeScalars.allSatisfy { $0.value >= 32 && $0.value != 127 && !forbidden.contains($0) }
        && имя(отображение.исходноеИмя) && имя(отображение.целевоеИмя)
        && отображение.исходноеИмя != отображение.целевоеИмя
        && !отображение.происхождение.isEmpty && отображение.происхождение.utf8.count <= 128
        && !отображение.происхождение.unicodeScalars.contains { $0.value < 32 || $0.value == 127 }
}

private func допустимыйИДОперации(_ s: String) -> Bool {
    !s.isEmpty && s.utf8.count <= 48 && s.utf8.allSatisfy {
        (65...90).contains($0) || (97...122).contains($0) || (48...57).contains($0) || [45, 46, 58, 95].contains($0)
    }
}

private func допустимСостав(_ cell: СнимокКорневойКлетки) -> Bool {
    guard !cell.поколение.isEmpty, cell.поколение.utf8.count <= 64,
          cell.поколение.utf8.allSatisfy({ $0 >= 33 && $0 <= 126 }),
          cell.записи.count <= 32_768,
          Set(cell.записи.map(\.относительныйПуть)).count == cell.записи.count else { return false }
    var budget = 0
    for record in cell.записи {
        let parts = record.относительныйПуть.split(separator: "/", omittingEmptySubsequences: false)
        guard !parts.isEmpty, parts.allSatisfy({ !$0.isEmpty && $0 != "." && $0 != ".." && $0.utf8.count <= 255 }),
              !record.относительныйПуть.hasPrefix("/"), !record.относительныйПуть.contains("\\"),
              record.относительныйПуть.utf8.count <= 1024,
              !record.относительныйПуть.unicodeScalars.contains(where: { $0.value == 0 || $0.value < 32 || $0.value == 127 }),
              record.вид != .внешняяГраница else { return false }
        let (newBudget, overflow) = budget.addingReportingOverflow(record.содержимое.count)
        guard !overflow, newBudget <= 64 * 1024 * 1024 else { return false }
        if record.вид == .каталог && !record.содержимое.isEmpty { return false }
        if record.вид == .ссылка {
            guard let target = String(data: record.содержимое, encoding: .utf8),
                  !target.isEmpty, !target.hasPrefix("/"), !target.contains("\\") else { return false }
            var depth = max(0, parts.count - 1)
            for component in target.split(separator: "/", omittingEmptySubsequences: false) {
                if component.isEmpty || component == "." { continue }
                if component == ".." {
                    guard depth > 0 else { return false }
                    depth -= 1
                } else { depth += 1 }
            }
        }
        budget = newBudget
    }
    return true
}

private func провереноВладение(_ cell: СнимокКорневойКлетки,
                               _ assignment: НазначениеКорневойКлетки) -> Bool {
    guard cell.назначение == assignment, cell.полныйОхват else { return false }
    guard case let .подтверждено(proof) = cell.проверкаВладения else { return false }
    return !proof.isEmpty && proof.utf8.count <= 256
}

private func состояниеКорня(_ cell: СнимокКорневойКлетки,
                            назначение: НазначениеКорневойКлетки, имя: String) -> Bool {
    cell.имяКорня == имя && допустимСостав(cell) && провереноВладение(cell, назначение)
}

private func построитьОжидаемыеЗаписи(источник: СнимокКорневойКлетки,
                                     цель: СнимокКорневойКлетки?,
                                     политика: ПолитикаСведенияКорней) -> [ЗаписьКорневойКлетки]? {
    guard политика == .равныеДедуплицироватьНепересекающиесяПеренестиРазличающиесяСохранить else {
        return nil
    }
    var byPath = Dictionary(uniqueKeysWithValues: (цель?.записи ?? []).map { ($0.относительныйПуть, $0) })
    for record in источник.записи {
        if let old = byPath[record.относительныйПуть] {
            guard old == record else { return nil }
        } else { byPath[record.относительныйПуть] = record }
    }
    let result = byPath.values.sorted { $0.относительныйПуть.utf8.lexicographicallyPrecedes($1.относительныйПуть.utf8) }
    let byResultPath = Dictionary(uniqueKeysWithValues: result.map { ($0.относительныйПуть, $0) })
    for record in result {
        var parent = record.относительныйПуть
        while let slash = parent.lastIndex(of: "/") {
            parent = String(parent[..<slash])
            if let parentRecord = byResultPath[parent], parentRecord.вид != .каталог { return nil }
        }
    }
    return result
}

private func путиКоллизий(источник: СнимокКорневойКлетки, цель: СнимокКорневойКлетки?) -> [String] {
    guard let цель else { return [] }
    let source = Dictionary(uniqueKeysWithValues: источник.записи.map { ($0.относительныйПуть, $0) })
    let target = Dictionary(uniqueKeysWithValues: цель.записи.map { ($0.относительныйПуть, $0) })
    var collisions = Set<String>()
    for path in Set(source.keys).intersection(target.keys) where source[path] != target[path] {
        collisions.insert(path)
    }
    for record in источник.записи + цель.записи {
        var parent = record.относительныйПуть
        while let slash = parent.lastIndex(of: "/") {
            parent = String(parent[..<slash])
            if let ancestor = source[parent] ?? target[parent], ancestor.вид != .каталог {
                collisions.insert(parent)
            }
        }
    }
    return collisions.sorted()
}

private func отпечаток(_ cell: СнимокКорневойКлетки) -> String {
    var bytes = Data()
    добавить(cell.назначение.идентификаторКлетки, в: &bytes)
    добавить(cell.назначение.владелец, в: &bytes)
    добавить(cell.назначение.ветка, в: &bytes)
    добавить(cell.имяКорня, в: &bytes)
    var count = UInt64(cell.записи.count).bigEndian
    withUnsafeBytes(of: &count) { bytes.append(contentsOf: $0) }
    for record in cell.записи {
        добавить(record.относительныйПуть, в: &bytes)
        добавить(record.вид.rawValue, в: &bytes)
        var owner = record.владелец.bigEndian
        withUnsafeBytes(of: &owner) { bytes.append(contentsOf: $0) }
        var mode = record.режим.bigEndian
        withUnsafeBytes(of: &mode) { bytes.append(contentsOf: $0) }
        добавить(record.содержимое, в: &bytes)
    }
    return SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
}

private func построитьНамерение(операция: String, назначение: НазначениеКорневойКлетки,
                                отображение: ОтображениеКорнейКлетки,
                                политика: ПолитикаСведенияКорней,
                                источник: СнимокКорневойКлетки, цель: СнимокКорневойКлетки?,
                                ожидаемаяЦель: [ЗаписьКорневойКлетки]) -> НамерениеСведенияКорней {
    let sourceDigest = отпечаток(источник)
    let targetDigest = цель.map(отпечаток)
    let sourceAuthority = текстСвидетельства(источник.проверкаВладения)
    let targetAuthority = цель.map { текстСвидетельства($0.проверкаВладения) } ?? "none"
    var bytes = Data()
    for component in [операция, назначение.идентификаторКлетки, назначение.владелец, назначение.ветка,
                      отображение.исходноеИмя, отображение.целевоеИмя, отображение.происхождение,
                      политика.rawValue, sourceDigest, источник.поколение, sourceAuthority,
                      targetDigest ?? "-", цель?.поколение ?? "none", targetAuthority] {
        добавить(component, в: &bytes)
    }
    let id = SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
    return .init(идентификаторОперации: операция, идентификаторНамерения: id,
        назначение: назначение, отображение: отображение, политика: политика,
        ожидаемыйИсходныйКорень: источник, ожидаемыйЦелевойКорень: цель,
        отпечатокИсходногоКорня: sourceDigest, отпечатокЦелевогоКорня: targetDigest,
        ожидаемыеЗаписиЦели: ожидаемаяЦель)
}

private func проверитьНамерение(_ intent: НамерениеСведенияКорней, операция: String,
                                 назначение: НазначениеКорневойКлетки,
                                 отображение: ОтображениеКорнейКлетки,
                                 политика: ПолитикаСведенияКорней) -> Bool {
    guard intent.идентификаторОперации == операция, intent.назначение == назначение,
          intent.отображение == отображение, intent.политика == политика,
          состояниеКорня(intent.ожидаемыйИсходныйКорень, назначение: назначение, имя: отображение.исходноеИмя),
          intent.ожидаемыйЦелевойКорень.map({
              состояниеКорня($0, назначение: назначение, имя: отображение.целевоеИмя)
          }) ?? true,
          intent.отпечатокИсходногоКорня == отпечаток(intent.ожидаемыйИсходныйКорень),
          intent.отпечатокЦелевогоКорня == intent.ожидаемыйЦелевойКорень.map(отпечаток),
          let expected = построитьОжидаемыеЗаписи(источник: intent.ожидаемыйИсходныйКорень,
              цель: intent.ожидаемыйЦелевойКорень, политика: политика),
          expected == intent.ожидаемыеЗаписиЦели else { return false }
    let rebuilt = построитьНамерение(операция: операция, назначение: назначение,
        отображение: отображение, политика: политика, источник: intent.ожидаемыйИсходныйКорень,
        цель: intent.ожидаемыйЦелевойКорень, ожидаемаяЦель: expected)
    return rebuilt.идентификаторНамерения == intent.идентификаторНамерения
}

private func совпадаетЦель(_ cell: СнимокКорневойКлетки,
                           intent: НамерениеСведенияКорней) -> Bool {
    cell.назначение == intent.назначение && cell.имяКорня == intent.отображение.целевоеИмя
        && cell.записи == intent.ожидаемыеЗаписиЦели && отпечаток(cell) == отпечатокОжидаемойЦели(intent)
        && cell.полныйОхват && провереноВладение(cell, intent.назначение)
}

private func отпечатокОжидаемойЦели(_ intent: НамерениеСведенияКорней) -> String {
    let generation = intent.ожидаемыйЦелевойКорень?.поколение ?? intent.ожидаемыйИсходныйКорень.поколение
    let proof = intent.ожидаемыйЦелевойКорень?.проверкаВладения ?? intent.ожидаемыйИсходныйКорень.проверкаВладения
    let expected = СнимокКорневойКлетки(назначение: intent.назначение,
        имяКорня: intent.отображение.целевоеИмя, поколение: generation, полныйОхват: true,
        проверкаВладения: proof, записи: intent.ожидаемыеЗаписиЦели)
    return отпечаток(expected)
}

private func текстЭффекта(_ intent: НамерениеСведенияКорней) -> String {
    "свести-корни:intent=\(intent.идентификаторНамерения):source=\(intent.отпечатокИсходногоКорня):target=\(intent.отпечатокЦелевогоКорня ?? "none"):expected_target=\(отпечатокОжидаемойЦели(intent)):map=\(intent.отображение.исходноеИмя)->\(intent.отображение.целевоеИмя):provenance=\(intent.отображение.происхождение)"
}

private func текстСвидетельства(_ evidence: ПроверкаВладенияКорневойКлеткой) -> String {
    switch evidence {
    case let .подтверждено(value): return "verified:\(value)"
    case let .неизвестно(reason): return "unknown:\(reason)"
    }
}

private func продолжение(_ intent: НамерениеСведенияКорней,
                         _ target: СнимокКорневойКлетки) -> ПродолжениеПланаКлетки {
    .init(назначение: intent.назначение, отображение: intent.отображение,
          идентификаторНамерения: intent.идентификаторНамерения,
          отпечатокЦелевогоКорня: отпечаток(target), целевойСнимок: target)
}

private func компонентСДлиной(_ s: String) -> String { "\(s.utf8.count)#\(s)" }
private func добавить(_ s: String, в d: inout Data) { добавить(Data(s.utf8), в: &d) }
private func добавить(_ data: Data, в d: inout Data) {
    var length = UInt64(data.count).bigEndian
    withUnsafeBytes(of: &length) { d.append(contentsOf: $0) }
    d.append(data)
}

private func принятьКоманду(_ context: КонтекстКомандыКлетки,
                            намерение: НамерениеСведенияКорней, фаза: ФазаКоманды,
                            такт: Int64, редуктор: inout Редуктор) throws {
    let suffix: String
    switch фаза { case .намерение: suffix = "-intent"; case .отправлена: suffix = "-sent"; case .принята: suffix = "-accepted" }
    try редуктор.принять(.init(идентификатор: context.операция + suffix,
        задача: context.задача, источник: context.источникКоманды, такт: такт,
        годноДо: Int64.max, охват: .точечный, область: context.область,
        исходныйФакт: "mapping provenance=\(намерение.отображение.происхождение); intent=\(намерение.идентификаторНамерения); source=\(намерение.отпечатокИсходногоКорня); target=\(намерение.отпечатокЦелевогоКорня ?? "none")",
        факт: .команда(операция: context.операция, фаза: фаза,
                       эффект: текстЭффекта(намерение), корректирует: nil)))
}

private func записатьПодтверждение(_ context: КонтекстКомандыКлетки,
                                   намерение: НамерениеСведенияКорней,
                                   наблюдение: НаблюдениеКорнейКлетки,
                                   цель: СнимокКорневойКлетки,
                                   редуктор: inout Редуктор) throws {
    let phase = редуктор.снимок.операции.first { $0.идентификатор == context.операция }?.фаза
    if phase == .намерение {
        try принятьКоманду(context, намерение: намерение, фаза: .отправлена,
            такт: max(context.первыйТакт + 1, редуктор.снимок.такт + 1), редуктор: &редуктор)
    }
    if phase == .намерение || phase == .отправлена {
        try принятьКоманду(context, намерение: намерение, фаза: .принята,
            такт: max(context.первыйТакт + 2, редуктор.снимок.такт + 1), редуктор: &редуктор)
    }
    guard редуктор.снимок.операции.first(where: { $0.идентификатор == context.операция })?.подтверждение == nil else { return }
    let sourceReadback = наблюдение.исходныйКорень.map(отпечаток) ?? "absent"
    let targetReadback = наблюдение.целевойКорень.map(отпечаток) ?? "absent"
    try редуктор.принять(.init(идентификатор: "подтверждение-\(намерение.идентификаторНамерения)",
        задача: context.задача, источник: context.источникНаблюдения,
        такт: max(context.первыйТакт + 3, редуктор.снимок.такт + 1), годноДо: Int64.max,
        охват: .точечный, область: context.область,
        исходныйФакт: "observed intent=\(намерение.идентификаторНамерения); source_sha256=\(sourceReadback); target_sha256=\(targetReadback); target_generation=\(цель.поколение); mapping=\(намерение.отображение.происхождение)",
        факт: .эффект(операция: context.операция, текст: текстЭффекта(намерение))))
}

private func проверитьДополнениеРедуктора(_ context: КонтекстКомандыКлетки,
                                          намерение: НамерениеСведенияКорней,
                                          подтверждение: Bool,
                                          редуктор: Редуктор) throws {
    let snapshot = редуктор.снимок
    let operation = snapshot.операции.first { $0.идентификатор == context.операция }
    guard snapshot.такт <= Int64.max - 4,
          snapshot.наблюдения.count <= БюджетСнимка.наблюдения - (подтверждение ? 2 : 4),
          (подтверждение ? operation?.подтверждение == nil : operation == nil),
          (подтверждение || snapshot.операции.count < 16),
          (подтверждение || context.первыйТакт > snapshot.такт) else {
        throw ОшибкаСведенияКлетки.неверныйКонтекстРедуктора
    }
    let commandIDs = ["-intent", "-sent", "-accepted"].map { context.операция + $0 }
    let observationID = "подтверждение-\(намерение.идентификаторНамерения)"
    let byID = Dictionary(uniqueKeysWithValues: snapshot.наблюдения.map { ($0.идентификатор, $0) })
    let commandCollision: Bool
    if подтверждение {
        commandCollision = commandIDs.contains { id in
            guard let existing = byID[id] else { return false }
            guard case let .команда(op, _, effect, _) = existing.факт else { return true }
            return op != context.операция || effect != текстЭффекта(намерение)
        }
    } else {
        commandCollision = commandIDs.contains { byID[$0] != nil }
    }
    guard Set(commandIDs).count == 3, (observationID + "-reserve").utf8.count <= 128,
          !commandCollision, byID[observationID] == nil else {
        throw ОшибкаСведенияКлетки.неверныйКонтекстРедуктора
    }
    var trial = редуктор
    if подтверждение {
        guard let operation, operation.ожидаемыйЭффект == текстЭффекта(намерение) else {
            throw ОшибкаСведенияКлетки.неверныйКонтекстРедуктора
        }
    } else {
        try принятьКоманду(context, намерение: намерение, фаза: .намерение,
            такт: context.первыйТакт, редуктор: &trial)
        try принятьКоманду(context, намерение: намерение, фаза: .отправлена,
            такт: context.первыйТакт + 1, редуктор: &trial)
    }
    let target = СнимокКорневойКлетки(назначение: намерение.назначение,
        имяКорня: намерение.отображение.целевоеИмя, поколение: "preflight-generation",
        полныйОхват: true, проверкаВладения: .подтверждено(свидетельство: "preflight"),
        записи: намерение.ожидаемыеЗаписиЦели)
    let obs = НаблюдениеКорнейКлетки(полныйОхват: true, исходныйКорень: nil, целевойКорень: target)
    try записатьПодтверждение(context, намерение: намерение, наблюдение: obs,
                              цель: target, редуктор: &trial)
}

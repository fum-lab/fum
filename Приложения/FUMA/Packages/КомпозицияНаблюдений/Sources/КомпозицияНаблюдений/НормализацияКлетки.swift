/// Durable intent фиксирует оба полных входа до эффекта. Отпечатки описывают
/// только поля выше и не доказывают полноту, если порт её не гарантирует.
public struct НамерениеСведенияКорней: Codable, Equatable, Sendable {
    public let идентификаторОперации: String
    public let идентификаторНамерения: String
    public let назначение: НазначениеКорневойКлетки
    public let отображение: ОтображениеКорнейКлетки
    public let политика: ПолитикаСведенияКорней
    public let ожидаемыйИсходныйКорень: СнимокКорневойКлетки
    public let ожидаемыйЦелевойКорень: СнимокКорневойКлетки?
    public let отпечатокИсходногоКорня: String
    public let отпечатокЦелевогоКорня: String?
    public let ожидаемыеЗаписиЦели: [ЗаписьКорневойКлетки]
    public init(идентификаторОперации: String, идентификаторНамерения: String,
                назначение: НазначениеКорневойКлетки, отображение: ОтображениеКорнейКлетки,
                политика: ПолитикаСведенияКорней, ожидаемыйИсходныйКорень: СнимокКорневойКлетки,
                ожидаемыйЦелевойКорень: СнимокКорневойКлетки?, отпечатокИсходногоКорня: String,
                отпечатокЦелевогоКорня: String?, ожидаемыеЗаписиЦели: [ЗаписьКорневойКлетки]) {
        self.идентификаторОперации = идентификаторОперации
        self.идентификаторНамерения = идентификаторНамерения
        self.назначение = назначение
        self.отображение = отображение
        self.политика = политика
        self.ожидаемыйИсходныйКорень = ожидаемыйИсходныйКорень
        self.ожидаемыйЦелевойКорень = ожидаемыйЦелевойКорень
        self.отпечатокИсходногоКорня = отпечатокИсходногоКорня
        self.отпечатокЦелевогоКорня = отпечатокЦелевогоКорня
        self.ожидаемыеЗаписиЦели = ожидаемыеЗаписиЦели
    }
}

public enum ИсходСведенияПорта: Equatable, Sendable {
    /// Порт сообщает только результат операции; успех подтверждает оператор
    /// исключительно новым наблюдением обоих корней и проверкой pinned intent.
    case эффектВозможен
    case обнаруженыРазличающиесяЗаписи(пути: [String])
}

/// Tools-owned adapter должен обеспечить назначение owner/ref, no-follow,
/// полный охват обоих корней, защиту от дрейфа и безопасное сведение.
/// Этот контракт не утверждает общую атомарность live filesystem.
public protocol ПортСведенияКорнейКлетки: Sendable {
    mutating func наблюдать(_ назначение: НазначениеКорневойКлетки,
                            отображение: ОтображениеКорнейКлетки) throws -> НаблюдениеКорнейКлетки
    mutating func сохранитьНамерение(_ намерение: НамерениеСведенияКорней) throws
    mutating func прочитатьНамерение(операция: String) throws -> НамерениеСведенияКорней?
    mutating func свестиКорни(_ намерение: НамерениеСведенияКорней) throws -> ИсходСведенияПорта
}

public struct КонтекстКомандыКлетки: Sendable {
    public let задача: Задача
    public let операция: String
    public let источникКоманды: Источник
    public let источникНаблюдения: Источник
    public let область: String
    public let первыйТакт: Int64
    public static func областьДля(_ назначение: НазначениеКорневойКлетки,
                                  _ отображение: ОтображениеКорнейКлетки,
                                  _ политика: ПолитикаСведенияКорней) -> String {
        "сведение-корней-v1:" + [назначение.идентификаторКлетки, назначение.владелец,
            назначение.ветка, отображение.исходноеИмя, отображение.целевоеИмя,
            отображение.происхождение, политика.rawValue].map(компонентСДлиной).joined()
    }
    public init(задача: Задача, операция: String, источникКоманды: Источник,
                источникНаблюдения: Источник, область: String, первыйТакт: Int64) {
        self.задача = задача
        self.операция = операция
        self.источникКоманды = источникКоманды
        self.источникНаблюдения = источникНаблюдения
        self.область = область
        self.первыйТакт = первыйТакт
    }
}


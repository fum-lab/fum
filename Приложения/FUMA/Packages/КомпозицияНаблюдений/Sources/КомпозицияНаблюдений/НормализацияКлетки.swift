public struct СнимокКорневойКлетки: Codable, Equatable, Sendable {
    public let назначение: НазначениеКорневойКлетки
    public let имяКорня: String
    public let поколение: String
    public let полныйОхват: Bool
    public let проверкаВладения: ПроверкаВладенияКорневойКлеткой
    public let записи: [ЗаписьКорневойКлетки]
    public init(назначение: НазначениеКорневойКлетки, имяКорня: String,
                поколение: String, полныйОхват: Bool,
                проверкаВладения: ПроверкаВладенияКорневойКлеткой,
                записи: [ЗаписьКорневойКлетки]) {

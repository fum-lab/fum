import Foundation
import CryptoKit
import АрхивныйСнимокЗадачи
import КонтейнерНаблюдений

public struct СсылкаПакетаВводаJSONL: Equatable, Sendable {
    public let идентификатор: String
}

public enum ИсходВводаJSONL: Equatable, Sendable {
    case записано(СсылкаПакетаВводаJSONL)
    case повтор(String)
    case сменаИсточника
    case дрейф
    case предел
    case неизвестныйИсход(идентификатор: String?, sha256Пакета: String?)
}

public enum ОшибкаВводаJSONL: Error, Equatable {
    case неверныйВход
    case несогласованнаяИстория
    case повреждение
}

/// В пакете сохраняется только прирост; хвост и прошлые рамки ссылаются на цепочку диапазонов.
public struct ПакетВводаJSONL: Codable, Equatable, Sendable {
    public let схема: String
    public let источник: String
    public let поколение: String
    public let предыдущий: String?
    public let начало: Int
    public let конец: Int
    public let сырыеНовыеБайты: Data
    public let хэшСреза: String
    public let префикс: ГраницаПрефикса
    public let началоХвоста: Int
    public let рамки: [ПозицияСтроки]
    /// Сумма длин срезов, переданных публичным сканерам; внутренние проходы не измерены.
    public let провереноБайтовСканерами: Int
    public let сохраненоСырыхБайтов: Int
}

private struct КурсорДляДекодирования: Encodable {
    let началоСреза: Int
    let префикс: ГраницаПрефикса
    let следующееСмещение: Int
    let неполныйХвост: Data
}

public struct ЦиклВводаJSONL: Sendable {
    private let пределБайтов: Int
    private static let тип = "fuma.пакет-ввода-jsonl.1"

    public init(пределБайтов: Int = 1_048_576) {
        self.пределБайтов = пределБайтов
    }

    /// История передаётся вызывающим как приватный каталог вне Git.
    /// Вход является полным ограниченным снимком, а не потоковым файловым API.
    public func принять(_ данные: Data, источник: String, поколение: String,
                        после: String?, история: URL,
                        операции: ФайловыеОперации = .системные) throws -> ИсходВводаJSONL {
        guard (1...1_048_576).contains(пределБайтов), !источник.isEmpty,
              источник.utf8.count <= 256, !поколение.isEmpty, поколение.utf8.count <= 256 else {
            throw ОшибкаВводаJSONL.неверныйВход
        }
        guard данные.count <= пределБайтов else { return .предел }
        let файлСегмента = история.appendingPathComponent("сегмент.fumobs")
        var предыдущийПакет: ПакетВводаJSONL?
        var открытыйЧитатель: Сегмент?
        defer { открытыйЧитатель?.закрыть() }
        if FileManager.default.fileExists(atPath: файлСегмента.path) {
            let читатель = try Сегмент(кореньДанных: история, запись: false, создать: false)
            открытыйЧитатель = читатель
            guard !читатель.естьХвост else { return .неизвестныйИсход(идентификатор: nil, sha256Пакета: nil) }
            let записи = читатель.записи.filter { $0.описание.тип == Self.тип }
            guard записи.last?.описание.идентификатор == после else {
                throw ОшибкаВводаJSONL.несогласованнаяИстория
            }
            if let после {
                предыдущийПакет = try прочитатьПакет(после, читатель: читатель)
            }
        } else if после != nil {
            throw ОшибкаВводаJSONL.несогласованнаяИстория
        }

        let прежнийКонец = предыдущийПакет?.конец ?? 0
        if let прежний = предыдущийПакет {
            guard прежний.источник == источник, прежний.поколение == поколение else {
                return .сменаИсточника
            }
            guard прежний.начало >= 0, прежнийКонец >= прежний.начало,
                  прежнийКонец <= данные.count else { return .дрейф }
            guard хэшВвода(Data(данные.prefix(прежнийКонец))) == прежний.хэшСреза else {
                return .дрейф
            }
        }

        let пределы = try ПределыПоследовательныхРамок(
            порция: пределБайтов, строка: min(262_144, пределБайтов),
            рамки: 1_000_000, байты: пределБайтов)
        var старыйКурсор: КурсорРамокJSONL?
        if предыдущийПакет != nil {
            let сканер = try ПоследовательныеРамкиJSONL(пределы: пределы)
            _ = try сканер.принять(Data(данные.prefix(прежнийКонец)), смещение: 0) { _ in }
            let итог = try сканер.завершить()
            let представление = КурсорДляДекодирования(
                началоСреза: 0, префикс: итог.префикс,
                следующееСмещение: итог.следующееСмещение, неполныйХвост: итог.сыройХвост)
            старыйКурсор = try JSONDecoder().decode(
                КурсорРамокJSONL.self, from: JSONEncoder().encode(представление))
            guard старыйКурсор?.префикс == предыдущийПакет?.префикс,
                  старыйКурсор?.префикс.байты == предыдущийПакет?.началоХвоста else {
                throw ОшибкаВводаJSONL.повреждение
            }
        }
        let исход: ИсходСверкиРамокJSONL
        do {
            исход = try сверитьРамкиJSONL(
                БайтовыйСрезJSONL(начало: 0, данные: данные), после: старыйКурсор, пределы: пределы)
        } catch ОшибкаАрхива.предел { return .предел }
        switch исход {
        case .повтор:
            guard let после else { throw ОшибкаВводаJSONL.повреждение }
            return .повтор(после)
        case .дрейф:
            return .дрейф
        case let .продолжение(рамки, _, курсор):
            let (проверено, переполнение) = (предыдущийПакет?.провереноБайтовСканерами ?? 0)
                .addingReportingOverflow(прежнийКонец + данные.count)
            guard !переполнение else { return .предел }
            let пакет = ПакетВводаJSONL(
                схема: Self.тип, источник: источник, поколение: поколение, предыдущий: после,
                начало: прежнийКонец, конец: данные.count,
                сырыеНовыеБайты: Data(данные.dropFirst(прежнийКонец)), хэшСреза: хэшВвода(данные),
                префикс: курсор.префикс, началоХвоста: курсор.префикс.байты,
                рамки: рамки.map(\.позиция), провереноБайтовСканерами: проверено,
                сохраненоСырыхБайтов: данные.count)
            let кодировщик = JSONEncoder()
            кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
            let байтыПакета = try кодировщик.encode(пакет)
            let идентификатор = "ввод-jsonl-" + UUID().uuidString.lowercased()
            let хэшПакета = хэшВвода(байтыПакета)
            let описание = ОписаниеНаблюдения(
                идентификатор: идентификатор, тип: Self.тип, источник: "КомпозицияНаблюдений",
                спецификация: Data(Self.тип.utf8))
            // После начала открытия на запись любой отказ требует отдельной сверки,
            // включая частичную запись, fsync и повторное открытие на чтение.
            открытыйЧитатель?.закрыть()
            открытыйЧитатель = nil
            do {
                let писатель = try Сегмент(кореньДанных: история, запись: true, создать: true, операции: операции)
                defer { писатель.закрыть() }
                guard !писатель.естьХвост,
                      писатель.записи.filter({ $0.описание.тип == Self.тип }).last?.описание.идентификатор == после else {
                    return .неизвестныйИсход(идентификатор: идентификатор, sha256Пакета: хэшПакета)
                }
                let квитанция = try писатель.добавить(описание, данные: байтыПакета)
                писатель.закрыть()
                let читатель = try Сегмент(кореньДанных: история, запись: false, создать: false)
                defer { читатель.закрыть() }
                guard !читатель.естьХвост,
                      читатель.записи.last == квитанция,
                      try читатель.извлечь(идентификатор) == байтыПакета,
                      try прочитатьПакет(идентификатор, читатель: читатель) == пакет else {
                    return .неизвестныйИсход(идентификатор: идентификатор, sha256Пакета: хэшПакета)
                }
                return .записано(СсылкаПакетаВводаJSONL(идентификатор: идентификатор))
            } catch {
                return .неизвестныйИсход(идентификатор: идентификатор, sha256Пакета: хэшПакета)
            }
        }
    }

    public func прочитать(_ идентификатор: String, история: URL) throws -> ПакетВводаJSONL {
        let читатель = try Сегмент(кореньДанных: история, запись: false, создать: false)
        defer { читатель.закрыть() }
        guard !читатель.естьХвост else { throw ОшибкаВводаJSONL.несогласованнаяИстория }
        return try прочитатьПакет(идентификатор, читатель: читатель)
    }

    public func числоПакетов(история: URL) throws -> Int {
        let читатель = try Сегмент(кореньДанных: история, запись: false, создать: false)
        defer { читатель.закрыть() }
        guard !читатель.естьХвост else { throw ОшибкаВводаJSONL.несогласованнаяИстория }
        return читатель.записи.filter { $0.описание.тип == Self.тип }.count
    }

    /// Только чтение: подтверждает видимый пакет, но не повторяет запись или fsync.
    public func подтвердить(_ идентификатор: String, sha256Пакета: String, история: URL) throws -> Bool {
        let читатель = try Сегмент(кореньДанных: история, запись: false, создать: false)
        defer { читатель.закрыть() }
        guard !читатель.естьХвост else { throw ОшибкаВводаJSONL.несогласованнаяИстория }
        guard let квитанция = читатель.записи.first(where: {
            $0.описание.идентификатор == идентификатор && $0.описание.тип == Self.тип
        }) else { return false }
        let байты = try читатель.извлечь(идентификатор)
        return квитанция.хэш == sha256Пакета && хэшВвода(байты) == sha256Пакета
    }

    /// В памяти один восстанавливаемый срез и один пакет, без массива прежних payload.
    public func восстановить(_ идентификатор: String, история: URL) throws -> Data {
        let читатель = try Сегмент(кореньДанных: история, запись: false, создать: false)
        defer { читатель.закрыть() }
        guard !читатель.естьХвост else { throw ОшибкаВводаJSONL.несогласованнаяИстория }
        let последний = try прочитатьПакет(идентификатор, читатель: читатель)
        guard последний.конец <= пределБайтов, последний.конец >= 0 else { throw ОшибкаВводаJSONL.повреждение }
        var данные = Data(repeating: 0, count: последний.конец)
        var ожидаемыйКонец = последний.конец
        var текущий: String? = идентификатор
        var посещены = Set<String>()
        while let ключ = текущий {
            guard посещены.insert(ключ).inserted else { throw ОшибкаВводаJSONL.повреждение }
            let пакет = try прочитатьПакет(ключ, читатель: читатель)
            guard пакет.источник == последний.источник, пакет.поколение == последний.поколение,
                  пакет.конец == ожидаемыйКонец, пакет.начало >= 0,
                  пакет.начало <= пакет.конец,
                  пакет.сырыеНовыеБайты.count == пакет.конец - пакет.начало else {
                throw ОшибкаВводаJSONL.повреждение
            }
            данные.replaceSubrange(пакет.начало..<пакет.конец, with: пакет.сырыеНовыеБайты)
            ожидаемыйКонец = пакет.начало
            текущий = пакет.предыдущий
        }
        guard ожидаемыйКонец == 0, хэшВвода(данные) == последний.хэшСреза else {
            throw ОшибкаВводаJSONL.повреждение
        }
        return данные
    }
}

private func прочитатьПакет(_ идентификатор: String, читатель: Сегмент) throws -> ПакетВводаJSONL {
    guard читатель.записи.contains(where: {
        $0.описание.идентификатор == идентификатор && $0.описание.тип == "fuma.пакет-ввода-jsonl.1"
    }) else { throw ОшибкаВводаJSONL.несогласованнаяИстория }
    let пакет = try JSONDecoder().decode(ПакетВводаJSONL.self, from: читатель.извлечь(идентификатор))
    guard пакет.схема == "fuma.пакет-ввода-jsonl.1" else { throw ОшибкаВводаJSONL.повреждение }
    return пакет
}

private func хэшВвода(_ данные: Data) -> String {
    SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
}

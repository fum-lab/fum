/// Не исполняет задания и не передаёт права. Возвращает детерминированный порядок локальной очереди.
public struct ПланЛокальнойОчереди: Encodable, Equatable, Sendable {
    public static let ожидаемаяСхема = "fuma.план-локальной-очереди.1"

    public let схема: String
    public let идентификаторНаблюдения: String
    public let исходныйАдрес: АдресЛокальногоУзла
    public let порядок: [ОценкаЛокальностиЗадания]

    fileprivate init(
        идентификаторНаблюдения: String,
        исходныйАдрес: АдресЛокальногоУзла,
        порядок: [ОценкаЛокальностиЗадания]
    ) {
        self.схема = Self.ожидаемаяСхема
        self.идентификаторНаблюдения = идентификаторНаблюдения
        self.исходныйАдрес = исходныйАдрес
        self.порядок = порядок
    }

    public func каноническаяСтрокаJSONL() throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        let bytes = try encoder.encode(self) + Data([0x0a])
        let framing = try выделитьРамкиПотока(bytes)
        guard framing.рамки.count == 1, framing.сыройХвост.isEmpty,
              framing.рамки[0].данные == bytes else {
            throw ОшибкаЛокальнойОчереди.очередьНеКанонизируется
        }
        return bytes
    }
}

/// Результат одного вызова планировщика с детерминированным счётчиком структурных операций.
/// Счётчик включает подготовку индекса один раз; при повторном использовании индекса
/// эти подготовительные значения относятся к общему снимку, а не к каждому вызову отдельно.
public struct РезультатУпорядочиванияЛокальнойОчереди: Equatable, Sendable {
    public let план: ПланЛокальнойОчереди
    public let счётчикРаботы: СчётчикРаботыЛокальнойОчереди

    fileprivate init(план: ПланЛокальнойОчереди, счётчикРаботы: СчётчикРаботыЛокальнойОчереди) {
        self.план = план
        self.счётчикРаботы = счётчикРаботы
    }
}

public enum РаспределительЛокальнойОчереди {
    public static func упорядочить(
        _ задания: [ЗаданиеЛокальнойОчереди],
        из исходногоАдреса: АдресЛокальногоУзла,
        по каталог: КаталогЛокальныхАдресов
    ) throws -> ПланЛокальнойОчереди {
        let индекс = try ИндексЛокальнойОчереди(
            каталог: каталог,
            исходныйАдрес: исходногоАдреса)
        return try упорядочитьСПодсчётом(задания, по: индекс).план
    }

    public static func упорядочить(
        _ задания: [ЗаданиеЛокальнойОчереди],
        по индекс: ИндексЛокальнойОчереди
    ) throws -> ПланЛокальнойОчереди {
        try упорядочитьСПодсчётом(задания, по: индекс).план
    }

    public static func упорядочитьСПодсчётом(
        _ задания: [ЗаданиеЛокальнойОчереди],
        по индекс: ИндексЛокальнойОчереди
    ) throws -> РезультатУпорядочиванияЛокальнойОчереди {
        var поисковВладельца = 0
        var поисковРасстояния = 0
        var полученийНабораХэшей = 0
        var проверокНаличияХэша = 0
        var сравненийСортировки = 0

        var идентификаторы = Set<String>()
        for задание in задания {
            guard !задание.идентификатор.isEmpty, задание.идентификатор.utf8.count <= 128,
                  идентификаторы.insert(задание.идентификатор).inserted else {
                throw ОшибкаЛокальнойОчереди.повторноеЗадание
            }
            поисковВладельца += 1
            guard let владелец = индекс.владелец(задание.адрес) else {
                throw ОшибкаЛокальнойОчереди.неизвестноеНазначение
            }
            guard владелец == задание.владелец else {
                throw ОшибкаЛокальнойОчереди.владелецНеСовпадает
            }
            guard Set(задание.требуемыеХэшиДанных).count == задание.требуемыеХэшиДанных.count,
                  задание.требуемыеХэшиДанных.allSatisfy(КаталогЛокальныхАдресов.допустимыйХэш) else {
                throw ОшибкаЛокальнойОчереди.недопустимыйХэшДанных
            }
        }

        var оценки: [ОценкаЛокальностиЗадания] = []
        for задание in задания {
            поисковРасстояния += 1
            guard let расстояние = индекс.расстояния[задание.адрес] else {
                throw ОшибкаЛокальнойОчереди.неизвестныйПутьГрафа
            }
            let совпадение = глубинаОбщегоПути(индекс.исходныйАдрес, задание.адрес)
            полученийНабораХэшей += 1
            let хэшиАдреса = индекс.хэшиДанных(задание.адрес)
            var доступно = 0
            for хэш in задание.требуемыеХэшиДанных {
                проверокНаличияХэша += 1
                if хэшиАдреса.contains(хэш) { доступно += 1 }
            }
            оценки.append(ОценкаЛокальностиЗадания(
                задание: задание,
                доступноТребуемыхДанных: доступно,
                расстояниеГрафа: расстояние,
                глубинаОбщегоРодителя: совпадение))
        }

        оценки.sort { левая, правая in
            сравненийСортировки += 1
            if левая.доступноТребуемыхДанных != правая.доступноТребуемыхДанных {
                return левая.доступноТребуемыхДанных > правая.доступноТребуемыхДанных
            }
            if левая.расстояниеГрафа != правая.расстояниеГрафа {
                return левая.расстояниеГрафа < правая.расстояниеГрафа
            }
            if левая.глубинаОбщегоРодителя != правая.глубинаОбщегоРодителя {
                return левая.глубинаОбщегоРодителя > правая.глубинаОбщегоРодителя
            }
            if левая.задание.стоимостьПередачиБайт != правая.задание.стоимостьПередачиБайт {
                return левая.задание.стоимостьПередачиБайт < правая.задание.стоимостьПередачиБайт
            }
            return левая.задание.идентификатор.utf8.lexicographicallyPrecedes(
                правая.задание.идентификатор.utf8)
        }

        let план = ПланЛокальнойОчереди(
            идентификаторНаблюдения: индекс.идентификаторНаблюдения,
            исходныйАдрес: индекс.исходныйАдрес,
            порядок: оценки)
        let счётчикРаботы = индекс.счётчикРаботы.дополняяПланирование(
            поисковВладельца: поисковВладельца,
            поисковРасстояния: поисковРасстояния,
            полученийНабораХэшей: полученийНабораХэшей,
            проверокНаличияХэша: проверокНаличияХэша,
            сравненийСортировки: сравненийСортировки)
        return РезультатУпорядочиванияЛокальнойОчереди(
            план: план,
            счётчикРаботы: счётчикРаботы)
    }

    private static func глубинаОбщегоПути(
        _ первый: АдресЛокальногоУзла,
        _ второй: АдресЛокальногоУзла
    ) -> Int {
        zip(первый.компоненты, второй.компоненты).prefix { $0.0 == $0.1 }.count
    }
}

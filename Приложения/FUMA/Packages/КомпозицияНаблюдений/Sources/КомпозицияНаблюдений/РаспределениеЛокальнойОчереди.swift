/// Соседняя связь для сотрудничества. Она не создаёт дочерний адрес и не меняет владельца.
public struct СвязьСотрудничества: Encodable, Equatable, Hashable, Sendable {
    public let первый: АдресЛокальногоУзла
    public let второй: АдресЛокальногоУзла

    public init(_ первый: АдресЛокальногоУзла, _ второй: АдресЛокальногоУзла) throws {
        guard первый != второй else { throw ОшибкаЛокальнойОчереди.неизвестнаяСвязь }
        if первый < второй {
            self.первый = первый
            self.второй = второй
        } else {
            self.первый = второй
            self.второй = первый
        }
    }
}


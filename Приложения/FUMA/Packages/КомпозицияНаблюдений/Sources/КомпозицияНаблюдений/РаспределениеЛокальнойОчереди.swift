public enum ОшибкаЛокальнойОчереди: Error, Equatable, Sendable {
    case недопустимыйАдрес
    case недопустимыйВладелец
    case недопустимыйПутьНаблюдения
    case снимокНеСовпадает
    case повторныйПутьНаблюдения
    case неизвестныйРодитель
    case неизвестнаяСвязь
    case повторнаяСвязь
    case неизвестноеНазначение
    case владелецНеСовпадает
    case повторноеЗадание
    case недопустимыйХэшДанных
    case источникВнеКаталога
    case неизвестныйПутьГрафа
    case очередьНеКанонизируется
}

/// Логический адрес узла. Это путь в адресной иерархии, не путь файловой системы.
public struct АдресЛокальногоУзла: Encodable, Hashable, Sendable, Comparable {
    public let компоненты: [String]

    public init(_ компоненты: [String]) throws {
        guard !компоненты.isEmpty, компоненты.count <= 64,
              компоненты.allSatisfy({ компонент in
                  !компонент.isEmpty && компонент.utf8.count <= 128 &&
                  компонент != "." && компонент != ".." &&
                  !компонент.contains("/") && !компонент.contains("\\") &&
                  !компонент.utf8.contains(0) &&
                  компонент == компонент.precomposedStringWithCanonicalMapping
              }) else {
            throw ОшибкаЛокальнойОчереди.недопустимыйАдрес
        }
        self.компоненты = компоненты
    }

    public var родитель: АдресЛокальногоУзла? {
        guard компоненты.count > 1 else { return nil }
        return try? АдресЛокальногоУзла(Array(компоненты.dropLast()))
    }

    public func дочерний(_ компонент: String) throws -> АдресЛокальногоУзла {
        try АдресЛокальногоУзла(компоненты + [компонент])
    }

    public var строка: String { компоненты.joined(separator: "/") }

    public static func < (lhs: Self, rhs: Self) -> Bool {
        lhs.строка.utf8.lexicographicallyPrecedes(rhs.строка.utf8)
    }
}

public enum ОшибкаЛокальнойОчереди: Error, Equatable, Sendable {
    case недопустимыйАдрес
    case недопустимыйВладелец
    case недопустимыйПутьНаблюдения
    case снимокНеСовпадает
    case повторныйПутьНаблюдения
    case неизвестныйРодитель
    case неизвестнаяСвязь
    case повторнаяСвязь
    case неизвестноеНазначение
    case владелецНеСовпадает
    case повторноеЗадание
    case недопустимыйХэшДанных
    case источникВнеКаталога
    case неизвестныйПутьГрафа
    case очередьНеКанонизируется
}

/// Логический адрес узла. Это путь в адресной иерархии, не путь файловой системы.
public struct АдресЛокальногоУзла: Encodable, Hashable, Sendable, Comparable {
    public let компоненты: [String]

    public init(_ компоненты: [String]) throws {
        guard !компоненты.isEmpty, компоненты.count <= 64,
              компоненты.allSatisfy({ компонент in
                  !компонент.isEmpty && компонент.utf8.count <= 128 &&
                  компонент != "." && компонент != ".." &&
                  !компонент.contains("/") && !компонент.contains("\\") &&
                  !компонент.utf8.contains(0) &&
                  компонент == компонент.precomposedStringWithCanonicalMapping
              }) else {
            throw ОшибкаЛокальнойОчереди.недопустимыйАдрес
        }
        self.компоненты = компоненты
    }

    public var родитель: АдресЛокальногоУзла? {
        guard компоненты.count > 1 else { return nil }
        return try? АдресЛокальногоУзла(Array(компоненты.dropLast()))
    }

    public func дочерний(_ компонент: String) throws -> АдресЛокальногоУзла {
        try АдресЛокальногоУзла(компоненты + [компонент])
    }

    public var строка: String { компоненты.joined(separator: "/") }

    public static func < (lhs: Self, rhs: Self) -> Bool {
        lhs.строка.utf8.lexicographicallyPrecedes(rhs.строка.utf8)
    }
}
public struct ПривязкаАдресаКФайлу: Encodable, Equatable, Sendable {
    public let адрес: АдресЛокальногоУзла
    public let относительныйПуть: String
    public let владелец: String

    public init(адрес: АдресЛокальногоУзла, относительныйПуть: String, владелец: String) {
        self.адрес = адрес
        self.относительныйПуть = относительныйПуть
        self.владелец = владелец
    }
}

/// Соседняя связь для сотрудничества. Она не создаёт дочерний адрес и не меняет владельца.
public struct СвязьСотрудничества: Encodable, Equatable, Hashable, Sendable {
    public let первый: АдресЛокальногоУзла
    public let второй: АдресЛокальногоУзла

    public init(_ первый: АдресЛокальногоУзла, _ второй: АдресЛокальногоУзла) throws {
        guard первый != второй else { throw ОшибкаЛокальнойОчереди.неизвестнаяСвязь }
        if первый < второй {
            self.первый = первый
            self.второй = второй
        } else {
            self.первый = второй
            self.второй = первый
        }
    }
}

public struct УзелЛокальногоКаталога: Encodable, Equatable, Sendable {
    public let адрес: АдресЛокальногоУзла
    public let владелец: String
    public let хэшиДоступныхДанных: [String]
}

/// Адресный каталог строится из одного завершённого наблюдения и явной локальной карты.
/// Физический корень и пути файлов остаются только во входном наблюдении и не сериализуются.
public struct КаталогЛокальныхАдресов: Encodable, Equatable, Sendable {
    public static let ожидаемаяСхема = "fuma.каталог-локальных-адресов.1"

    public let схема: String
    public let идентификаторНаблюдения: String
    public let корень: АдресЛокальногоУзла
    public let узлы: [УзелЛокальногоКаталога]
    public let связиСотрудничества: [СвязьСотрудничества]

    public init(
        наблюдение: ПроекцияФайловойСистемы,
        корень: АдресЛокальногоУзла,
        владелецКорня: String,
        привязки: [ПривязкаАдресаКФайлу],
        связиСотрудничества: [СвязьСотрудничества] = []
    ) throws {
        guard Self.допустимВладелец(владелецКорня),
              Self.допустимыйХэш(наблюдение.идентификатор),
              !наблюдение.источник.isEmpty,
              !наблюдение.физическийКорень.isEmpty else {
            throw ОшибкаЛокальнойОчереди.снимокНеСовпадает
        }

        var файлы: [String: ПроекцияЗаписиФайловойСистемы] = [:]
        for запись in наблюдение.записи {
            guard Self.допустимыйПуть(запись.путь),
                  Self.допустимыйХэш(запись.хэш),
                  файлы.updateValue(запись, forKey: запись.путь) == nil else {
                throw ОшибкаЛокальнойОчереди.снимокНеСовпадает
            }
        }

        var владельцы: [АдресЛокальногоУзла: String] = [корень: владелецКорня]
        var данные: [АдресЛокальногоУзла: Set<String>] = [корень: []]
        var использованныеПути = Set<String>()
        for привязка in привязки {
            guard привязка.адрес != корень,
                  привязка.адрес.компоненты.starts(with: корень.компоненты),
                  привязка.адрес.родитель != nil,
                  Self.допустимВладелец(привязка.владелец),
                  Self.допустимыйПуть(привязка.относительныйПуть),
                  let файл = файлы[привязка.относительныйПуть], файл.тип == "файл" else {
                throw ОшибкаЛокальнойОчереди.недопустимыйПутьНаблюдения
            }
            guard использованныеПути.insert(привязка.относительныйПуть).inserted else {
                throw ОшибкаЛокальнойОчереди.повторныйПутьНаблюдения
            }
            if let прежнийВладелец = владельцы[привязка.адрес], прежнийВладелец != привязка.владелец {
                throw ОшибкаЛокальнойОчереди.владелецНеСовпадает
            }
            владельцы[привязка.адрес] = привязка.владелец
            данные[привязка.адрес, default: []].insert(файл.хэш)
        }

        for адрес in владельцы.keys where адрес != корень {
            guard let родитель = адрес.родитель, владельцы[родитель] != nil else {
                throw ОшибкаЛокальнойОчереди.неизвестныйРодитель
            }
        }

        let множествоСвязей = Set(связиСотрудничества)
        guard множествоСвязей.count == связиСотрудничества.count else {
            throw ОшибкаЛокальнойОчереди.повторнаяСвязь
        }
        guard связиСотрудничества.allSatisfy({ владельцы[$0.первый] != nil && владельцы[$0.второй] != nil }) else {
            throw ОшибкаЛокальнойОчереди.неизвестнаяСвязь
        }

        self.схема = Self.ожидаемаяСхема
        self.идентификаторНаблюдения = наблюдение.идентификатор
        self.корень = корень
        self.узлы = владельцы.keys.sorted().compactMap { адрес in
            guard let владелец = владельцы[адрес] else { return nil }
            return УзелЛокальногоКаталога(
                адрес: адрес,
                владелец: владелец,
                хэшиДоступныхДанных: (данные[адрес] ?? []).sorted())
        }
        self.связиСотрудничества = связиСотрудничества.sorted {
            if $0.первый == $1.первый { return $0.второй < $1.второй }
            return $0.первый < $1.первый
        }
    }

    public func дочерниеАдреса(_ адрес: АдресЛокальногоУзла) -> [АдресЛокальногоУзла] {
        узлы.map(\.адрес).filter { $0.родитель == адрес }.sorted()
    }

    fileprivate func владелец(_ адрес: АдресЛокальногоУзла) -> String? {
        узлы.first(where: { $0.адрес == адрес })?.владелец
    }

    fileprivate func хэшиДанных(_ адрес: АдресЛокальногоУзла) -> Set<String> {
        Set(узлы.first(where: { $0.адрес == адрес })?.хэшиДоступныхДанных ?? [])
    }

    fileprivate func соседи() -> [АдресЛокальногоУзла: Set<АдресЛокальногоУзла>] {
        var результат = Dictionary(uniqueKeysWithValues: узлы.map { ($0.адрес, Set<АдресЛокальногоУзла>()) })
        for узел in узлы {
            if let родитель = узел.адрес.родитель, результат[родитель] != nil {
                результат[узел.адрес, default: []].insert(родитель)
                результат[родитель, default: []].insert(узел.адрес)
            }
        }
        for связь in связиСотрудничества {
            результат[связь.первый, default: []].insert(связь.второй)
            результат[связь.второй, default: []].insert(связь.первый)
        }
        return результат
    }

    fileprivate static func допустимВладелец(_ значение: String) -> Bool {
        !значение.isEmpty && значение.utf8.count <= 128 && !значение.utf8.contains(0)
    }

    fileprivate static func допустимыйПуть(_ путь: String) -> Bool {
        guard !путь.isEmpty, путь.utf8.count <= 1024, путь.first != "/",
              !путь.utf8.contains(0), путь == путь.precomposedStringWithCanonicalMapping else { return false }
        let части = путь.split(separator: "/", omittingEmptySubsequences: false)
        return !части.isEmpty && части.allSatisfy { !$0.isEmpty && $0 != "." && $0 != ".." }
    }

    fileprivate static func допустимыйХэш(_ хэш: String) -> Bool {
        хэш.utf8.count == 64 && хэш.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
}

public struct ЗаданиеЛокальнойОчереди: Encodable, Equatable, Sendable {
    public let идентификатор: String
    public let адрес: АдресЛокальногоУзла
    public let владелец: String
    public let требуемыеХэшиДанных: [String]
    public let стоимостьПередачиБайт: UInt64

    public init(
        идентификатор: String,
        адрес: АдресЛокальногоУзла,
        владелец: String,
        требуемыеХэшиДанных: [String],
        стоимостьПередачиБайт: UInt64
    ) {
        self.идентификатор = идентификатор
        self.адрес = адрес
        self.владелец = владелец
        self.требуемыеХэшиДанных = требуемыеХэшиДанных.sorted()
        self.стоимостьПередачиБайт = стоимостьПередачиБайт
    }
}

public struct ОценкаЛокальностиЗадания: Encodable, Equatable, Sendable {
    public let задание: ЗаданиеЛокальнойОчереди
    public let доступноТребуемыхДанных: Int
    public let расстояниеГрафа: Int
    public let глубинаОбщегоРодителя: Int
}

/// Не исполняет задания и не передаёт права. Возвращает детерминированный порядок локальной очереди.
public struct ПланЛокальнойОчереди: Encodable, Equatable, Sendable {
    public static let ожидаемаяСхема = "fuma.план-локальной-очереди.1"

    public let схема: String
    public let идентификаторНаблюдения: String
    public let исходныйАдрес: АдресЛокальногоУзла
    public let порядок: [ОценкаЛокальностиЗадания]

    fileprivate init(
        идентификаторНаблюдения: String,
        исходныйАдрес: АдресЛокальногоУзла,
        порядок: [ОценкаЛокальностиЗадания]
    ) {
        self.схема = Self.ожидаемаяСхема
        self.идентификаторНаблюдения = идентификаторНаблюдения
        self.исходныйАдрес = исходныйАдрес
        self.порядок = порядок
    }

    public func каноническаяСтрокаJSONL() throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        let bytes = try encoder.encode(self) + Data([0x0a])
        let framing = try выделитьРамкиПотока(bytes)
        guard framing.рамки.count == 1, framing.сыройХвост.isEmpty,
              framing.рамки[0].данные == bytes else {
            throw ОшибкаЛокальнойОчереди.очередьНеКанонизируется
        }
        return bytes
    }
}

public enum РаспределительЛокальнойОчереди {
    public static func упорядочить(
        _ задания: [ЗаданиеЛокальнойОчереди],
        из исходногоАдреса: АдресЛокальногоУзла,
        по каталог: КаталогЛокальныхАдресов
    ) throws -> ПланЛокальнойОчереди {
        guard каталог.владелец(исходногоАдреса) != nil else {
            throw ОшибкаЛокальнойОчереди.источникВнеКаталога
        }

        var идентификаторы = Set<String>()
        for задание in задания {
            guard !задание.идентификатор.isEmpty, задание.идентификатор.utf8.count <= 128,
                  идентификаторы.insert(задание.идентификатор).inserted else {
                throw ОшибкаЛокальнойОчереди.повторноеЗадание
            }
            guard let владелец = каталог.владелец(задание.адрес) else {
                throw ОшибкаЛокальнойОчереди.неизвестноеНазначение
            }
            guard владелец == задание.владелец else {
                throw ОшибкаЛокальнойОчереди.владелецНеСовпадает
            }
            guard Set(задание.требуемыеХэшиДанных).count == задание.требуемыеХэшиДанных.count,
                  задание.требуемыеХэшиДанных.allSatisfy(КаталогЛокальныхАдресов.допустимыйХэш) else {
                throw ОшибкаЛокальнойОчереди.недопустимыйХэшДанных
            }
        }

        let смежность = каталог.соседи()
        let расстояния = расстоянияОтИсходногоАдреса(исходногоАдреса, смежность: смежность)
        var оценки: [ОценкаЛокальностиЗадания] = []
        for задание in задания {
            guard let расстояние = расстояния[задание.адрес] else {
                throw ОшибкаЛокальнойОчереди.неизвестныйПутьГрафа
            }
            let совпадение = глубинаОбщегоПути(исходногоАдреса, задание.адрес)
            let нужные = Set(задание.требуемыеХэшиДанных)
            let доступно = нужные.intersection(каталог.хэшиДанных(задание.адрес)).count
            оценки.append(ОценкаЛокальностиЗадания(
                задание: задание,
                доступноТребуемыхДанных: доступно,
                расстояниеГрафа: расстояние,
                глубинаОбщегоРодителя: совпадение))
        }

        оценки.sort { левая, правая in
            if левая.доступноТребуемыхДанных != правая.доступноТребуемыхДанных {
                return левая.доступноТребуемыхДанных > правая.доступноТребуемыхДанных
            }
            if левая.расстояниеГрафа != правая.расстояниеГрафа {
                return левая.расстояниеГрафа < правая.расстояниеГрафа
            }
            if левая.глубинаОбщегоРодителя != правая.глубинаОбщегоРодителя {
                return левая.глубинаОбщегоРодителя > правая.глубинаОбщегоРодителя
            }
            if левая.задание.стоимостьПередачиБайт != правая.задание.стоимостьПередачиБайт {
                return левая.задание.стоимостьПередачиБайт < правая.задание.стоимостьПередачиБайт
            }
            return левая.задание.идентификатор.utf8.lexicographicallyPrecedes(
                правая.задание.идентификатор.utf8)
        }

        return ПланЛокальнойОчереди(
            идентификаторНаблюдения: каталог.идентификаторНаблюдения,
            исходныйАдрес: исходногоАдреса,
            порядок: оценки)
    }

    private static func расстоянияОтИсходногоАдреса(
        _ исходныйАдрес: АдресЛокальногоУзла,
        смежность: [АдресЛокальногоУзла: Set<АдресЛокальногоУзла>]
    ) -> [АдресЛокальногоУзла: Int] {
        var расстояния = [исходныйАдрес: 0]
        var очередь = [исходныйАдрес]
        var следующий = 0
        while следующий < очередь.count {
            let адрес = очередь[следующий]
            следующий += 1
            guard let расстояние = расстояния[адрес] else { continue }
            for сосед in (смежность[адрес] ?? []).sorted() where расстояния[сосед] == nil {
                расстояния[сосед] = расстояние + 1
                очередь.append(сосед)
            }
        }
        return расстояния
    }

    private static func глубинаОбщегоПути(
        _ первый: АдресЛокальногоУзла,
        _ второй: АдресЛокальногоУзла
    ) -> Int {
        zip(первый.компоненты, второй.компоненты).prefix { $0.0 == $0.1 }.count
    }
}

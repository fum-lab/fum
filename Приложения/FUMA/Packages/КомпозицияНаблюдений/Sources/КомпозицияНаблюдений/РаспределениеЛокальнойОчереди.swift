/// Адресный каталог строится из одного завершённого наблюдения и явной локальной карты.
/// Физический корень и пути файлов остаются только во входном наблюдении и не сериализуются.
public struct КаталогЛокальныхАдресов: Encodable, Equatable, Sendable {
    public static let ожидаемаяСхема = "fuma.каталог-локальных-адресов.1"

    public let схема: String
    public let идентификаторНаблюдения: String
    public let корень: АдресЛокальногоУзла
    public let узлы: [УзелЛокальногоКаталога]
    public let связиСотрудничества: [СвязьСотрудничества]

    public init(
        наблюдение: ПроекцияФайловойСистемы,
        корень: АдресЛокальногоУзла,
        владелецКорня: String,
        привязки: [ПривязкаАдресаКФайлу],
        связиСотрудничества: [СвязьСотрудничества] = []
    ) throws {
        guard Self.допустимВладелец(владелецКорня),
              Self.допустимыйХэш(наблюдение.идентификатор),
              !наблюдение.источник.isEmpty,
              !наблюдение.физическийКорень.isEmpty else {
            throw ОшибкаЛокальнойОчереди.снимокНеСовпадает
        }

        var файлы: [String: ПроекцияЗаписиФайловойСистемы] = [:]
        for запись in наблюдение.записи {
            guard Self.допустимыйПуть(запись.путь),
                  Self.допустимыйХэш(запись.хэш),
                  файлы.updateValue(запись, forKey: запись.путь) == nil else {
                throw ОшибкаЛокальнойОчереди.снимокНеСовпадает
            }
        }

        var владельцы: [АдресЛокальногоУзла: String] = [корень: владелецКорня]
        var данные: [АдресЛокальногоУзла: Set<String>] = [корень: []]
        var использованныеПути = Set<String>()
        for привязка in привязки {
            guard привязка.адрес != корень,
                  привязка.адрес.компоненты.starts(with: корень.компоненты),
                  привязка.адрес.родитель != nil,
                  Self.допустимВладелец(привязка.владелец),
                  Self.допустимыйПуть(привязка.относительныйПуть),
                  let файл = файлы[привязка.относительныйПуть], файл.тип == "файл" else {
                throw ОшибкаЛокальнойОчереди.недопустимыйПутьНаблюдения
            }
            guard использованныеПути.insert(привязка.относительныйПуть).inserted else {
                throw ОшибкаЛокальнойОчереди.повторныйПутьНаблюдения
            }
            if let прежнийВладелец = владельцы[привязка.адрес], прежнийВладелец != привязка.владелец {
                throw ОшибкаЛокальнойОчереди.владелецНеСовпадает
            }
            владельцы[привязка.адрес] = привязка.владелец
            данные[привязка.адрес, default: []].insert(файл.хэш)
        }

        for адрес in владельцы.keys where адрес != корень {
            guard let родитель = адрес.родитель, владельцы[родитель] != nil else {
                throw ОшибкаЛокальнойОчереди.неизвестныйРодитель
            }
        }

        let множествоСвязей = Set(связиСотрудничества)
        guard множествоСвязей.count == связиСотрудничества.count else {
            throw ОшибкаЛокальнойОчереди.повторнаяСвязь
        }
        guard связиСотрудничества.allSatisfy({ владельцы[$0.первый] != nil && владельцы[$0.второй] != nil }) else {
            throw ОшибкаЛокальнойОчереди.неизвестнаяСвязь
        }

        self.схема = Self.ожидаемаяСхема
        self.идентификаторНаблюдения = наблюдение.идентификатор
        self.корень = корень
        self.узлы = владельцы.keys.sorted().compactMap { адрес in
            guard let владелец = владельцы[адрес] else { return nil }
            return УзелЛокальногоКаталога(
                адрес: адрес,
                владелец: владелец,
                хэшиДоступныхДанных: (данные[адрес] ?? []).sorted())
        }
        self.связиСотрудничества = связиСотрудничества.sorted {
            if $0.первый == $1.первый { return $0.второй < $1.второй }
            return $0.первый < $1.первый
        }
    }

    public func дочерниеАдреса(_ адрес: АдресЛокальногоУзла) -> [АдресЛокальногоУзла] {
        узлы.map(\.адрес).filter { $0.родитель == адрес }.sorted()
    }

    fileprivate static func допустимВладелец(_ значение: String) -> Bool {
        !значение.isEmpty && значение.utf8.count <= 128 && !значение.utf8.contains(0)
    }

    fileprivate static func допустимыйПуть(_ путь: String) -> Bool {
        guard !путь.isEmpty, путь.utf8.count <= 1024, путь.first != "/",
              !путь.utf8.contains(0), путь == путь.precomposedStringWithCanonicalMapping else { return false }
        let части = путь.split(separator: "/", omittingEmptySubsequences: false)
        return !части.isEmpty && части.allSatisfy { !$0.isEmpty && $0 != "." && $0 != ".." }
    }

    fileprivate static func допустимыйХэш(_ хэш: String) -> Bool {
        хэш.utf8.count == 64 && хэш.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
}

/// Раздельно считает структуру построения/BFS, обращения к индексам и сравнения сортировки.
/// Это число наблюдаемых операций, не замер времени или полной CPU-сложности.
public struct СчётчикРаботыЛокальнойОчереди: Equatable, Sendable {
    public let построенныхУзловИндекса: Int
    public let построенныхХэшейИндекса: Int
    public let построенныхСвязейИндекса: Int
    public let посещённыхВершин: Int
    /// Просмотренные записи смежности: каждое направление неориентированного ребра считается отдельно.
    public let просмотренныхРёбер: Int
    public let поисковВладельца: Int
    public let поисковРасстояния: Int
    public let полученийНабораХэшей: Int
    public let проверокНаличияХэша: Int
    public let сравненийСортировки: Int

    /// Объём подготовки индекса и обхода; сравнения сортировки сюда не входят.
    public var подготовкаИндекса: Int {
        построенныхУзловИндекса + построенныхХэшейИндекса + построенныхСвязейИндекса +
        посещённыхВершин + просмотренныхРёбер
    }

    fileprivate init(
        построенныхУзловИндекса: Int,
        построенныхХэшейИндекса: Int,
        построенныхСвязейИндекса: Int,
        посещённыхВершин: Int,
        просмотренныхРёбер: Int,
        поисковВладельца: Int = 0,
        поисковРасстояния: Int = 0,
        полученийНабораХэшей: Int = 0,
        проверокНаличияХэша: Int = 0,
        сравненийСортировки: Int = 0
    ) {
        self.построенныхУзловИндекса = построенныхУзловИндекса
        self.построенныхХэшейИндекса = построенныхХэшейИндекса
        self.построенныхСвязейИндекса = построенныхСвязейИндекса
        self.посещённыхВершин = посещённыхВершин
        self.просмотренныхРёбер = просмотренныхРёбер
        self.поисковВладельца = поисковВладельца
        self.поисковРасстояния = поисковРасстояния
        self.полученийНабораХэшей = полученийНабораХэшей
        self.проверокНаличияХэша = проверокНаличияХэша
        self.сравненийСортировки = сравненийСортировки
    }

    fileprivate func дополняяПланирование(
        поисковВладельца: Int,
        поисковРасстояния: Int,
        полученийНабораХэшей: Int,
        проверокНаличияХэша: Int,
        сравненийСортировки: Int
    ) -> Self {
        Self(
            построенныхУзловИндекса: построенныхУзловИндекса,
            построенныхХэшейИндекса: построенныхХэшейИндекса,
            построенныхСвязейИндекса: построенныхСвязейИндекса,
            посещённыхВершин: посещённыхВершин,
            просмотренныхРёбер: просмотренныхРёбер,
            поисковВладельца: поисковВладельца,
            поисковРасстояния: поисковРасстояния,
            полученийНабораХэшей: полученийНабораХэшей,
            проверокНаличияХэша: проверокНаличияХэша,
            сравненийСортировки: сравненийСортировки)
    }
}

/// Неизменяемое представление каталога для повторного планирования от одного источника.
/// Индекс содержит только логические адреса и метаданные исходного каталога.
public struct ИндексЛокальнойОчереди: Sendable {
    public let идентификаторНаблюдения: String
    public let исходныйАдрес: АдресЛокальногоУзла
    /// Счётчик подготовки и BFS. Он строится один раз вместе с индексом.
    public let счётчикРаботы: СчётчикРаботыЛокальнойОчереди

    fileprivate let владельцы: [АдресЛокальногоУзла: String]
    fileprivate let хэши: [АдресЛокальногоУзла: Set<String>]
    fileprivate let дети: [АдресЛокальногоУзла: [АдресЛокальногоУзла]]
    fileprivate let расстояния: [АдресЛокальногоУзла: Int]

    public init(
        каталог: КаталогЛокальныхАдресов,
        исходныйАдрес: АдресЛокальногоУзла
    ) throws {
        var владельцы: [АдресЛокальногоУзла: String] = [:]
        var хэши: [АдресЛокальногоУзла: Set<String>] = [:]
        var дети: [АдресЛокальногоУзла: [АдресЛокальногоУзла]] = [:]
        var смежность = Dictionary(
            uniqueKeysWithValues: каталог.узлы.map { ($0.адрес, Set<АдресЛокальногоУзла>()) })
        var числоХэшей = 0
        var числоСвязей = 0

        for узел in каталог.узлы {
            владельцы[узел.адрес] = узел.владелец
            хэши[узел.адрес] = Set(узел.хэшиДоступныхДанных)
            числоХэшей += узел.хэшиДоступныхДанных.count

            if let родитель = узел.адрес.родитель {
                дети[родитель, default: []].append(узел.адрес)
                смежность[узел.адрес, default: []].insert(родитель)
                смежность[родитель, default: []].insert(узел.адрес)
                числоСвязей += 1
            }
        }
        for связь in каталог.связиСотрудничества {
            смежность[связь.первый, default: []].insert(связь.второй)
            смежность[связь.второй, default: []].insert(связь.первый)
            числоСвязей += 1
        }

        guard владельцы[исходныйАдрес] != nil else {
            throw ОшибкаЛокальнойОчереди.источникВнеКаталога
        }

        var расстояния = [исходныйАдрес: 0]
        var очередь = [исходныйАдрес]
        var следующий = 0
        var просмотренныхСмежностей = 0
        while следующий < очередь.count {
            let адрес = очередь[следующий]
            следующий += 1
            guard let расстояние = расстояния[адрес] else { continue }
            let соседи = смежность[адрес] ?? []
            просмотренныхСмежностей += соседи.count
            for сосед in соседи where расстояния[сосед] == nil {
                расстояния[сосед] = расстояние + 1
                очередь.append(сосед)
            }
        }

        self.идентификаторНаблюдения = каталог.идентификаторНаблюдения
        self.исходныйАдрес = исходныйАдрес
        self.владельцы = владельцы
        self.хэши = хэши
        self.дети = дети
        self.расстояния = расстояния
        self.счётчикРаботы = СчётчикРаботыЛокальнойОчереди(
            построенныхУзловИндекса: каталог.узлы.count,
            построенныхХэшейИндекса: числоХэшей,
            построенныхСвязейИндекса: числоСвязей,
            посещённыхВершин: расстояния.count,
            просмотренныхРёбер: просмотренныхСмежностей)
    }

    public func дочерниеАдреса(_ адрес: АдресЛокальногоУзла) -> [АдресЛокальногоУзла] {
        дети[адрес] ?? []
    }

    fileprivate func владелец(_ адрес: АдресЛокальногоУзла) -> String? {
        владельцы[адрес]
    }

    fileprivate func хэшиДанных(_ адрес: АдресЛокальногоУзла) -> Set<String> {
        хэши[адрес] ?? []
    }
}


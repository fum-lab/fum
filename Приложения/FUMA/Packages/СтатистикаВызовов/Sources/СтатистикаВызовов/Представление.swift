import Foundation

public func разметкаСтатистики(_ отчёт: ОтчётСтатистики) -> String {
    var строки = ["# Статистика вызовов", "", "Задача: `" + отчёт.задача + "`. Контракт: `" + отчёт.контракт + "`.", "",
        "Прямых идентифицированных вызовов: " + String(отчёт.прямыхВызовов) + ". Сопряжённых результатов: " +
        String(отчёт.сопряжённыхРезультатов) + ". Несопряжённых результатов: " + String(отчёт.несопряжённыхРезультатов) +
        ". Вызовов без идентичности: " + String(отчёт.вызовыБезИдентичности.count) + ". Точных дублей: " +
        String(отчёт.дубликатов) + ".", "",
        "Output не доказывает успех; задержка между наблюдёнными timestamps не является временем исполнения. " +
        "Неизвестные и отрицательные интервалы не заменяются нулём. Универсальных порогов нет.", ""]
    if let г = отчёт.граница {
        строки += ["Подтверждённый префикс: " + String(г.байт) + " байт, " + String(г.строк) +
            " строк, SHA-256 `" + г.sha256 + "`.", ""]
    } else { строки += ["Подтверждённого префикса пока нет.", ""] }
    строки += ["| Инструмент | Вызовы | Без ID | Пары | Без результата | Неоднозначно | Неизвестная задержка | Наблюдённая задержка, нс |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
    for и in отчёт.инструменты {
        let интервал = и.задержкиНаносекунды.first.map { String($0) + "…" + String(и.задержкиНаносекунды.last!) } ?? "неизвестно"
        строки.append("| " + [и.инструмент ?? "неизвестно", String(и.прямыхВызовов), String(и.вызововБезИдентичности),
            String(и.сопряжённыхРезультатов), String(и.безРезультата), String(и.неоднозначныхСвязей),
            String(и.неизвестныхЗадержек), интервал].joined(separator: " | ") + " |")
    }
    строки += ["", "## Происхождение нормализованных событий", "",
        "Диапазоны [начало, конец) и SHA включают LF. Хэши не являются анонимизацией. Полные arguments/output не сохранены.", "",
        "| Строка | Байты [начало, конец) | Направление | Call ID | Инструмент | SHA-256 |",
        "| ---: | --- | --- | --- | --- | --- |"]
    for с in отчёт.наблюдения {
        let п = с.происхождение
        строки.append("| " + [String(п.строка), "[" + String(п.начало) + ", " + String(п.конец) + ")",
            с.направление.rawValue, с.идентификатор ?? "неизвестно", с.инструмент ?? "неизвестно", п.sha256]
            .joined(separator: " | ") + " |")
    }
    return строки.joined(separator: "\n") + "\n"
}

private final class СборщикХода: @unchecked Sendable {
    private let синхронизатор = NSLock()
    private var значения: [ЭтапПодготовкиТоррента] = []

    var этапы: [ЭтапПодготовкиТоррента] {
        синхронизатор.lock()
        defer { синхронизатор.unlock() }
        return значения
    }

    func добавитьЭтап(_ этап: ЭтапПодготовкиТоррента) {
        синхронизатор.lock()
        значения.insert(этап, at: значения.endIndex)
        синхронизатор.unlock()
    }
}

private final class НаблюдательРостаИсточника: @unchecked Sendable {
    private let адрес: URL
    private let синхронизатор = NSLock()
    private(set) var ошибкаЗаписи: String?
    private(set) var источникНаращён = false
    private(set) var опубликованХодСверхЛимита = false

    init(адрес: URL) { self.адрес = адрес }

    func наблюдать(_ ход: ХодПодготовкиТоррента) {
        guard ход.этап == .хэшИсточника else { return }
        синхронизатор.lock()
        defer { синхронизатор.unlock() }
        опубликованХодСверхЛимита = опубликованХодСверхЛимита || ход.завершено > ход.всего
        guard !источникНаращён else { return }
        do {
            let запись = try FileHandle(forWritingTo: адрес)
            defer { try? запись.close() }
            try запись.seekToEnd()
            try запись.write(contentsOf: Data(repeating: 0x42, count: 1024 * 1024))
            источникНаращён = true
        } catch {
            ошибкаЗаписи = String(describing: error)
        }
    }
}

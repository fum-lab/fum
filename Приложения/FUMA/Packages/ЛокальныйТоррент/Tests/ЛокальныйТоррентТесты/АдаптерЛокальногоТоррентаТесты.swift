    func test_ОтклоняетИменованныйКаналБезОжиданияПисателя() async throws {
        let адрес = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        XCTAssertEqual(Darwin.mkfifo(адрес.path, mode_t(S_IRUSR | S_IWUSR)), 0)
        defer { try? FileManager.default.removeItem(at: адрес) }
        let адаптер = АдаптерЛокальногоТоррента(обработчик: ПостоянныйОбработчик(результат: try примерМетаданных()))
        let часы = ContinuousClock()
        let начало = часы.now
        let аварийноеОсвобождение = Task.detached {
            do { try await Task.sleep(for: .seconds(1)) } catch { return }
            while !Task.isCancelled {
                let дескриптор = Darwin.open(адрес.path, O_WRONLY | O_NONBLOCK | O_CLOEXEC)
                if дескриптор >= 0 {
                    Darwin.close(дескриптор)
                    return
                }
                do { try await Task.sleep(for: .milliseconds(10)) } catch { return }
            }
        }

        do {
            _ = try await адаптер.подготовить(файл: ВыборЛокальногоФайла(адрес: адрес), ограничения: ограничения())
            XCTFail("FIFO должен отклоняться до ожидания внешнего писателя")
        } catch {
            XCTAssertEqual(error as? ОшибкаПодготовкиТоррента, .источникНеОбычныйФайл)
        }
        let длительность = начало.duration(to: часы.now)
        аварийноеОсвобождение.cancel()
        await аварийноеОсвобождение.value
        XCTAssertLessThan(длительность, .milliseconds(500))
    }


private actor НаблюдающийОбработчик: ОбработчикМетаданныхТоррента {
    let результат: СозданныеМетаданныеТоррента
    private(set) var полученныйХэш: String?
    private(set) var полученныеОграничения: ОграниченияПодготовкиТоррента?

    init(результат: СозданныеМетаданныеТоррента) { self.результат = результат }

    func создать(
        адресФайла: URL,
        имяФайла: String,
        размерФайла: UInt64,
        ожидаемыйХэшСодержимого: String,
        ограничения: ОграниченияПодготовкиТоррента,
        отмена: ОтменаПодготовкиТоррента,
        ход: @escaping @Sendable (ХодПодготовкиТоррента) -> Void
    ) async throws -> СозданныеМетаданныеТоррента {
        try отмена.проверитьОтмену()
        полученныйХэш = ожидаемыйХэшСодержимого
        полученныеОграничения = ограничения
        return результат
    }
}


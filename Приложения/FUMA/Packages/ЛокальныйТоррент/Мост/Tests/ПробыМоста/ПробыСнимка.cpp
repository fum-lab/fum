struct КонтекстПробыСнимка {
    int случай;
    uint64_t размер;
    ОперацияТоррента const* операция;
    int чтений = 0;
    int записей = 0;
    int хвостов = 0;
    int писатель = -1;
    std::string путь_подмены;
};

ssize_t прочитать_для_пробы(void* указатель, int дескриптор, void* буфер, size_t длина, off_t позиция) {
    auto& контекст = *static_cast<КонтекстПробыСнимка*>(указатель);
    ++контекст.чтений;
    if (static_cast<uint64_t>(позиция) == контекст.размер) {
        ++контекст.хвостов;
        if (контекст.случай == 7) {
            отменить_операцию_торрента(const_cast<ОперацияТоррента*>(контекст.операция)); errno = EINTR; return -1;
        }
    }
    if (контекст.случай == 1 && контекст.чтений == 1) { errno = EINTR; return -1; }
    if (контекст.случай == 3 && контекст.чтений > 1) { errno = EIO; return -1; }
    return pread(дескриптор, буфер, контекст.случай == 1 ? std::min<size_t>(длина, 1700) : длина, позиция);
}

ssize_t записать_для_пробы(void* указатель, int дескриптор, void const* буфер, size_t длина, off_t позиция) {
    auto& контекст = *static_cast<КонтекстПробыСнимка*>(указатель);
    контекст.писатель = дескриптор; ++контекст.записей;
    if (контекст.случай == 1 && контекст.записей == 1) { errno = EINTR; return -1; }
    if (контекст.случай == 2 && контекст.записей > 1) return 0;
    if (контекст.случай == 4 && контекст.записей > 1) { errno = ENOSPC; return -1; }
    auto записано = pwrite(дескриптор, буфер, контекст.случай == 1 ? std::min<size_t>(длина, 1300) : длина, позиция);
    if (контекст.случай == 5 && записано > 0 && static_cast<uint64_t>(позиция + записано) == контекст.размер) {
        uint8_t байт = 255;
        if (pwrite(дескриптор, &байт, 1, 0) != 1) throw std::runtime_error("не сработала подмена байта пробы");
    }
    if (контекст.случай == 6 && записано > 0) отменить_операцию_торрента(const_cast<ОперацияТоррента*>(контекст.операция));
    if ((контекст.случай == 8 || контекст.случай == 9) && записано > 0
            && static_cast<uint64_t>(позиция + записано) == контекст.размер) {
        char путь[4096]{};
        if (fcntl(дескриптор, F_GETPATH, путь) != 0) throw std::runtime_error("не получен путь пробы");
        контекст.путь_подмены = путь;
        if (unlink(путь) != 0) throw std::runtime_error("не сработала подмена имени");
        if (контекст.случай == 9) {
            if (mkfifo(путь, 0600) != 0) throw std::runtime_error("не создан FIFO пробы");
        } else {
            auto маркер = open(путь, O_WRONLY | O_CREAT | O_EXCL | O_CLOEXEC, 0600);
            if (маркер < 0) throw std::runtime_error("не создан маркер пробы");
            auto принято = write(маркер, "M", 1); close(маркер);
            if (принято != 1) throw std::runtime_error("не записан маркер пробы");
        }
    }
    return записано;
}

extern "C" РезультатГраницыМоста выполнить_пробу_снимка(
    int32_t исходник, int32_t каталог, char const* имя, size_t длина_имени,
    uint64_t ожидаемый_размер, uint64_t максимум_байт, uint8_t const* хэш,
    ОперацияТоррента const* операция, НаблюдениеСнимкаФайла* наблюдение) {
    return выполнить_пробу_снимка_с_ошибкой(исходник, каталог, имя, длина_имени,
        ожидаемый_размер, максимум_байт, хэш, операция, наблюдение, 0);
}

extern "C" РезультатГраницыМоста выполнить_пробу_снимка_с_ошибкой(
    int32_t исходник, int32_t каталог, char const* имя, size_t длина_имени,
    uint64_t ожидаемый_размер, uint64_t максимум_байт, uint8_t const* хэш,
    ОперацияТоррента const* операция, НаблюдениеСнимкаФайла* наблюдение, int32_t случай) {
    КонтекстПробыСнимка контекст{случай, ожидаемый_размер, операция};
    auto итог = выполнить_без_исключений([&] {
        if (хэш == nullptr || наблюдение == nullptr) {
            throw std::invalid_argument("отсутствует вход пробы");
        }
        auto const первоначальная_позиция = lseek(исходник, 0, SEEK_CUR);
        auto const первоначальные_флаги = fcntl(исходник, F_GETFL);
        auto const первоначальные_флаги_дескриптора = fcntl(исходник, F_GETFD);
        auto const флаги_каталога = fcntl(каталог, F_GETFL);
        auto const флаги_дескриптора_каталога = fcntl(каталог, F_GETFD);
        struct stat исходник_до{}, каталог_до{};
        if (fstat(исходник, &исходник_до) != 0 || fstat(каталог, &каталог_до) != 0) {
            throw std::system_error(errno, std::generic_category());
        }
        std::array<uint8_t, 32> ожидаемый_хэш{};
        std::memcpy(ожидаемый_хэш.data(), хэш, ожидаемый_хэш.size());
        auto снимок = создать_снимок_файла(исходник, каталог, имя, длина_имени,
            ожидаемый_размер, максимум_байт, ожидаемый_хэш, операция,
            ПримитивыСнимка{&контекст, прочитать_для_пробы, записать_для_пробы, nullptr});
        struct stat файл{}, папка{}, родитель{}, именованный_файл{}, исходник_после{}, каталог_после{};
        std::string точное_имя(имя, длина_имени);
        if (fstat(снимок->дескриптор_файла(), &файл) != 0
            || fstat(снимок->дескриптор_каталога(), &папка) != 0
            || fstatat(снимок->дескриптор_каталога(), "..", &родитель, 0) != 0
            || fstatat(снимок->дескриптор_каталога(), точное_имя.c_str(), &именованный_файл,
                AT_SYMLINK_NOFOLLOW) != 0
            || fstat(исходник, &исходник_после) != 0 || fstat(каталог, &каталог_после) != 0) {
            throw std::system_error(errno, std::generic_category());
        }
        if (файл.st_size < 0 || static_cast<uint64_t>(файл.st_size) != ожидаемый_размер) {
            throw std::runtime_error("неверный размер снимка");
        }
        НаблюдениеСнимкаФайла результат{};
        результат.права_файла = файл.st_mode & 07777;
        результат.права_каталога = папка.st_mode & 07777;
        результат.позиция_сохранена = lseek(исходник, 0, SEEK_CUR) == первоначальная_позиция;
        результат.флаги_сохранены = fcntl(исходник, F_GETFL) == первоначальные_флаги
            && fcntl(исходник, F_GETFD) == первоначальные_флаги_дескриптора
            && fcntl(каталог, F_GETFL) == флаги_каталога
            && fcntl(каталог, F_GETFD) == флаги_дескриптора_каталога
            && исходник_после.st_dev == исходник_до.st_dev
            && исходник_после.st_ino == исходник_до.st_ino
            && исходник_после.st_mode == исходник_до.st_mode
            && каталог_после.st_dev == каталог_до.st_dev
            && каталог_после.st_ino == каталог_до.st_ino
            && каталог_после.st_mode == каталог_до.st_mode;
        результат.снимок_независим = S_ISREG(файл.st_mode)
            && (файл.st_dev != исходник_до.st_dev || файл.st_ino != исходник_до.st_ino);
        результат.каталог_дочерний = S_ISDIR(папка.st_mode)
            && (папка.st_dev != каталог_до.st_dev || папка.st_ino != каталог_до.st_ino)
            && родитель.st_dev == каталог_до.st_dev && родитель.st_ino == каталог_до.st_ino;
        результат.файл_принадлежит_каталогу = S_ISREG(именованный_файл.st_mode)
            && именованный_файл.st_dev == файл.st_dev && именованный_файл.st_ino == файл.st_ino;
        auto const флаги_снимка = fcntl(снимок->дескриптор_файла(), F_GETFL);
        auto const флаги_дескриптора_снимка = fcntl(снимок->дескриптор_файла(), F_GETFD);
        auto const флаги_дескриптора_папки_снимка = fcntl(снимок->дескриптор_каталога(), F_GETFD);
        результат.только_чтение = флаги_снимка >= 0 && (флаги_снимка & O_ACCMODE) == O_RDONLY
            && флаги_дескриптора_снимка >= 0 && (флаги_дескриптора_снимка & FD_CLOEXEC) != 0;
        результат.каталог_закрывается_при_исполнении = флаги_дескриптора_папки_снимка >= 0
            && (флаги_дескриптора_папки_снимка & FD_CLOEXEC) != 0;
        CC_SHA256_CTX вычислитель{};
        if (CC_SHA256_Init(&вычислитель) != 1) throw std::runtime_error("отказ SHA-256");
        std::array<uint8_t, 16384> буфер{};
        while (результат.байтов < ожидаемый_размер) {
            auto const остаток = ожидаемый_размер - результат.байтов;
            auto const размер = остаток < буфер.size() ? static_cast<size_t>(остаток) : буфер.size();
            auto прочитано = pread(снимок->дескриптор_файла(), буфер.data(), размер,
                static_cast<off_t>(результат.байтов));
            if (прочитано < 0 && errno == EINTR) continue;
            if (прочитано <= 0) throw std::runtime_error("снимок неполон");
            if (CC_SHA256_Update(&вычислитель, буфер.data(), static_cast<CC_LONG>(прочитано)) != 1) {
                throw std::runtime_error("отказ SHA-256");
            }
            результат.байтов += static_cast<uint64_t>(прочитано);
        }
        if (CC_SHA256_Final(результат.хэш, &вычислитель) != 1) throw std::runtime_error("отказ SHA-256");
        снимок->удалить_с_проверкой();
        *наблюдение = результат;
    });
    if (наблюдение) {
        наблюдение->вызовов_чтения = контекст.чтений;
        наблюдение->вызовов_записи = контекст.записей;
        наблюдение->проб_хвоста = контекст.хвостов;
        наблюдение->писатель_закрыт = контекст.писатель < 0 || (fcntl(контекст.писатель, F_GETFD) == -1 && errno == EBADF);
        if (!контекст.путь_подмены.empty()) {
            struct stat объект{};
            наблюдение->подмена_сохранена = lstat(контекст.путь_подмены.c_str(), &объект) == 0
                && (контекст.случай == 9 ? S_ISFIFO(объект.st_mode) : S_ISREG(объект.st_mode));
            // Маркер принадлежит тестовой стороне. Она убирает его после наблюдения.
            unlink(контекст.путь_подмены.c_str());
            auto родитель = контекст.путь_подмены.substr(0, контекст.путь_подмены.find_last_of('/'));
            rmdir(родитель.c_str());
        }
    }
    return итог;
}

void проверить_отмену_метаданных(ВходМостаТоррента const& вход) {
    if (запрошена_отмена_торрента(вход.операция)
        || (вход.проверка_отмены && вход.проверка_отмены(вход.контекст))) throw ОтменаОперацииМоста{};
}
bool шестнадцатеричный_хэш(std::string const& хэш, size_t длина) {
    if (хэш.size() != длина) return false;
    for (auto байт : хэш) if (!((байт >= '0' && байт <= '9') || (байт >= 'a' && байт <= 'f'))) return false;
    return true;
}
struct БюджетМетаданных {
    uint64_t число_частей;
    size_t размер_бенкода;
};

uint64_t сложить_размеры(uint64_t первый, uint64_t второй) {
    if (второй > std::numeric_limits<uint64_t>::max() - первый)
        throw std::invalid_argument("переполнение размера метаданных");
    return первый + второй;
}

uint64_t умножить_размеры(uint64_t первый, uint64_t второй) {
    if (первый != 0 && второй > std::numeric_limits<uint64_t>::max() / первый)
        throw std::invalid_argument("переполнение размера метаданных");
    return первый * второй;
}

uint64_t число_цифр(uint64_t число) {
    uint64_t результат = 1;
    while (число >= 10) {
        число /= 10;
        ++результат;
    }
    return результат;
}

uint64_t размер_строки_бенкода(uint64_t длина) {
    return сложить_размеры(сложить_размеры(число_цифр(длина), 1), длина);
}

uint64_t размер_целого_бенкода(uint64_t число) {
    return сложить_размеры(число_цифр(число), 2);
}

БюджетМетаданных рассчитать_бюджет_метаданных(
    ВходМостаТоррента const& вход) {
    auto размер = вход.размер;
    auto часть = вход.длина_части;
    if (размер == 0 || размер > вход.максимум_файла
        || размер > static_cast<uint64_t>(libtorrent::file_storage::max_file_size)
        || часть < 16384 || часть > 128 * 1024 * 1024
        || (часть & (часть - 1)) != 0
        || вход.длина_имени == 0 || вход.длина_имени > 255
        || вход.максимум_метаданных == 0
        || размер > static_cast<uint64_t>(std::numeric_limits<int64_t>::max())
                         - (часть - 1))
        throw std::invalid_argument("неверный размер или бюджет метаданных");

    uint64_t число = (размер - 1) / часть + 1;
    if (число > static_cast<uint64_t>(std::numeric_limits<int>::max()))
        throw std::invalid_argument("слишком много частей");

    uint64_t итог = число == 1 ? 158 : 193;
    итог = сложить_размеры(итог,
        умножить_размеры(2, размер_строки_бенкода(вход.длина_имени)));
    итог = сложить_размеры(итог,
        умножить_размеры(2, размер_целого_бенкода(размер)));
    итог = сложить_размеры(итог, размер_целого_бенкода(часть));
    итог = сложить_размеры(итог,
        размер_строки_бенкода(умножить_размеры(20, число)));
    if (число > 1)
        итог = сложить_размеры(итог,
            размер_строки_бенкода(умножить_размеры(32, число)));

    if (итог > вход.максимум_метаданных
        || итог > static_cast<uint64_t>(std::numeric_limits<int>::max())
        || итог > static_cast<uint64_t>(std::numeric_limits<size_t>::max()))
        throw std::invalid_argument("бюджет метаданных превышен");

    return {число, static_cast<size_t>(итог)};
}

[[noreturn]] void отказ_носителя_провайдера() {
    int ошибка = errno;
    throw std::system_error(ошибка, std::generic_category(),
                           "не удалось проверить снимок");
}

bool одинаковые_метки_провайдера(
    struct stat const& первый, struct stat const& второй) {
    return первый.st_dev == второй.st_dev
        && первый.st_ino == второй.st_ino
        && первый.st_mode == второй.st_mode
        && первый.st_uid == второй.st_uid
        && первый.st_gid == второй.st_gid
        && первый.st_nlink == второй.st_nlink
        && первый.st_size == второй.st_size
        && первый.st_mtimespec.tv_sec == второй.st_mtimespec.tv_sec
        && первый.st_mtimespec.tv_nsec == второй.st_mtimespec.tv_nsec
        && первый.st_ctimespec.tv_sec == второй.st_ctimespec.tv_sec
        && первый.st_ctimespec.tv_nsec == второй.st_ctimespec.tv_nsec;
}

std::string путь_дескриптора_провайдера(int дескриптор) {
    std::array<char, MAXPATHLEN> путь{};
    if (::fcntl(дескриптор, F_GETPATH, путь.data()) != 0)
        отказ_носителя_провайдера();
    if (путь[0] != '/'
        || std::memchr(путь.data(), '\0', путь.size()) == nullptr)
        throw std::runtime_error("неверный физический путь снимка");
    return std::string(путь.data());
}

struct НаблюдениеСнимкаПровайдера {
    std::string путь_каталога;
    struct stat каталог{};
    struct stat файл{};
};

НаблюдениеСнимкаПровайдера наблюдать_снимок_провайдера(
    СнимокФайла const& снимок, ВходМостаТоррента const& вход) {
    НаблюдениеСнимкаПровайдера результат;
    struct stat именованный_каталог{}, именованный_файл{};
    struct stat путь_каталога{}, путь_файла{};

    if (::fstat(снимок.дескриптор_каталога(), &результат.каталог) != 0
        || ::fstat(снимок.дескриптор_файла(), &результат.файл) != 0
        || ::fstatat(снимок.родитель, снимок.имя_каталога.c_str(),
                    &именованный_каталог, AT_SYMLINK_NOFOLLOW) != 0
        || ::fstatat(снимок.дескриптор_каталога(), снимок.имя_файла.c_str(),
                    &именованный_файл, AT_SYMLINK_NOFOLLOW) != 0)
        отказ_носителя_провайдера();

    int флаги = ::fcntl(снимок.дескриптор_файла(), F_GETFL);
    int наследование_файла = ::fcntl(снимок.дескриптор_файла(), F_GETFD);
    int наследование_каталога = ::fcntl(снимок.дескриптор_каталога(), F_GETFD);
    if (флаги < 0 || наследование_файла < 0 || наследование_каталога < 0)
        отказ_носителя_провайдера();

    результат.путь_каталога =
        путь_дескриптора_провайдера(снимок.дескриптор_каталога());
    std::string полный_путь =
        результат.путь_каталога + "/" + снимок.имя_файла;
    if (::lstat(результат.путь_каталога.c_str(), &путь_каталога) != 0
        || ::lstat(полный_путь.c_str(), &путь_файла) != 0)
        отказ_носителя_провайдера();

    if (!S_ISDIR(результат.каталог.st_mode)
        || (результат.каталог.st_mode & 07777) != 0700
        || !S_ISREG(результат.файл.st_mode)
        || (результат.файл.st_mode & 07777) != 0400
        || результат.файл.st_nlink != 1
        || результат.файл.st_size < 0
        || static_cast<uint64_t>(результат.файл.st_size) != вход.размер
        || (флаги & O_ACCMODE) != O_RDONLY
        || (наследование_файла & FD_CLOEXEC) == 0
        || (наследование_каталога & FD_CLOEXEC) == 0
        || результат.каталог.st_dev != снимок.метка_каталога.st_dev
        || результат.каталог.st_ino != снимок.метка_каталога.st_ino
        || результат.файл.st_dev != снимок.метка_файла.st_dev
        || результат.файл.st_ino != снимок.метка_файла.st_ino
        || !одинаковые_метки_провайдера(
               результат.каталог, именованный_каталог)
        || !одинаковые_метки_провайдера(
               результат.каталог, путь_каталога)
        || !одинаковые_метки_провайдера(
               результат.файл, именованный_файл)
        || !одинаковые_метки_провайдера(
               результат.файл, путь_файла)
        || путь_дескриптора_провайдера(
               снимок.дескриптор_файла()) != полный_путь)
        throw std::runtime_error("имя или дескриптор снимка подменён");

    return результат;
}

void сверить_наблюдение_снимка(
    СнимокФайла const& снимок, ВходМостаТоррента const& вход,
    НаблюдениеСнимкаПровайдера const& раньше) {
    auto сейчас = наблюдать_снимок_провайдера(снимок, вход);
    if (сейчас.путь_каталога != раньше.путь_каталога
        || !одинаковые_метки_провайдера(сейчас.каталог, раньше.каталог)
        || !одинаковые_метки_провайдера(сейчас.файл, раньше.файл))
        throw std::runtime_error("снимок изменился во время провайдера");
}

struct КонтекстПроизводственногоПровайдера {
    ВходМостаТоррента вход{};
    std::array<uint8_t, 32> хэш{};
};

void сверить_содержимое_снимка(
    СнимокФайла const& снимок,
    КонтекстПроизводственногоПровайдера const& контекст) {
    CC_SHA256_CTX вычислитель{};
    if (CC_SHA256_Init(&вычислитель) != 1)
        throw std::runtime_error("отказ SHA-256 снимка");
    std::array<uint8_t, 65536> буфер{};
    uint64_t позиция = 0;
    while (позиция < контекст.вход.размер) {
        проверить_отмену_метаданных(контекст.вход);
        size_t длина = static_cast<size_t>(std::min<uint64_t>(
            буфер.size(), контекст.вход.размер - позиция));
        ssize_t прочитано = ::pread(снимок.дескриптор_файла(),
            буфер.data(), длина, static_cast<off_t>(позиция));
        if (прочитано < 0 && errno == EINTR) continue;
        if (прочитано < 0) отказ_носителя_провайдера();
        if (прочитано == 0)
            throw std::runtime_error("снимок стал короче");
        if (CC_SHA256_Update(&вычислитель, буфер.data(),
                static_cast<CC_LONG>(прочитано)) != 1)
            throw std::runtime_error("отказ SHA-256 снимка");
        позиция += static_cast<uint64_t>(прочитано);
    }

    uint8_t хвост{};
    ssize_t прочитано;
    do {
        проверить_отмену_метаданных(контекст.вход);
        прочитано = ::pread(снимок.дескриптор_файла(), &хвост, 1,
            static_cast<off_t>(контекст.вход.размер));
    } while (прочитано < 0 && errno == EINTR);
    if (прочитано < 0) отказ_носителя_провайдера();

    std::array<uint8_t, 32> хэш{};
    if (CC_SHA256_Final(хэш.data(), &вычислитель) != 1)
        throw std::runtime_error("отказ SHA-256 снимка");
    if (прочитано != 0 || хэш != контекст.хэш)
        throw std::runtime_error("байты снимка изменились");
}

std::string представить_хэш_метаданных(uint8_t const* хэш, size_t длина) {
    std::string результат;
    результат.reserve(длина * 2);
    char const* цифры = "0123456789abcdef";
    for (size_t номер = 0; номер < длина; ++номер) {
        результат += цифры[хэш[номер] >> 4];
        результат += цифры[хэш[номер] & 15];
    }
    return результат;
}

БайтыМетаданных произвести_библиотечные_метаданные(
    void* указатель, СнимокФайла const& снимок) {
    auto const& контекст =
        *static_cast<КонтекстПроизводственногоПровайдера const*>(указатель);
    auto const& вход = контекст.вход;
    auto бюджет = рассчитать_бюджет_метаданных(вход);
    проверить_отмену_метаданных(вход);
    auto наблюдение = наблюдать_снимок_провайдера(снимок, вход);

    std::vector<libtorrent::create_file_entry> файлы;
    файлы.emplace_back(снимок.имя_файла,
                       static_cast<int64_t>(вход.размер));
    libtorrent::create_torrent создание(
        std::move(файлы), static_cast<int>(вход.длина_части), {});
    создание.set_creation_date(0);
    if (создание.is_v1_only() || создание.is_v2_only()
        || создание.num_pieces() != static_cast<int>(бюджет.число_частей))
        throw std::runtime_error("неверный hybrid-профиль библиотеки");

    libtorrent::settings_pack настройки;
    настройки.set_int(libtorrent::settings_pack::aio_threads, 0);
    настройки.set_int(libtorrent::settings_pack::hashing_threads, 1);
    libtorrent::error_code ошибка;
    libtorrent::set_piece_hashes(
        создание, наблюдение.путь_каталога, настройки,
        libtorrent::posix_disk_io_constructor,
        [&](libtorrent::piece_index_t номер) {
            static_cast<void>(номер);
            проверить_отмену_метаданных(вход);
        }, ошибка);
    проверить_отмену_метаданных(вход);
    if (ошибка)
        throw std::runtime_error(
            "libtorrent не прочитал снимок: " + ошибка.message());

    сверить_наблюдение_снимка(снимок, вход, наблюдение);
    сверить_содержимое_снимка(снимок, контекст);
    сверить_наблюдение_снимка(снимок, вход, наблюдение);
    проверить_отмену_метаданных(вход);

    auto буфер = создание.generate_buf();
    проверить_отмену_метаданных(вход);
    if (буфер.size() != бюджет.размер_бенкода
        || буфер.size() > вход.максимум_метаданных)
        throw std::runtime_error("размер bencode не совпал с точным бюджетом");

    libtorrent::bdecode_node дерево;
    libtorrent::error_code ошибка_разбора;
    int предел_токенов = static_cast<int>(буфер.size());
    if (libtorrent::bdecode(буфер.data(), буфер.data() + буфер.size(),
            дерево, ошибка_разбора, nullptr, 32, предел_токенов) != 0
        || ошибка_разбора
        || дерево.type() != libtorrent::bdecode_node::dict_t
        || дерево.data_section().size()
               != static_cast<ptrdiff_t>(буфер.size()))
        throw std::runtime_error("не удалось разобрать готовый bencode");

    auto информация = дерево.dict_find_dict("info");
    auto точные_байты = информация.data_section();
    if (информация.type() != libtorrent::bdecode_node::dict_t
        || точные_байты.size() <= 0)
        throw std::runtime_error("отсутствуют точные байты info");

    std::array<uint8_t, 20> первый{};
    std::array<uint8_t, 32> второй{};
    if (!CC_SHA1(точные_байты.data(),
            static_cast<CC_LONG>(точные_байты.size()), первый.data())
        || !CC_SHA256(точные_байты.data(),
            static_cast<CC_LONG>(точные_байты.size()), второй.data()))
        throw std::runtime_error("отказ вычисления infohash");

    проверить_отмену_метаданных(вход);
    сверить_наблюдение_снимка(снимок, вход, наблюдение);
    return {
        std::vector<uint8_t>(буфер.begin(), буфер.end()),
        представить_хэш_метаданных(первый.data(), первый.size()),
        представить_хэш_метаданных(второй.data(), второй.size())
    };
}

struct МетаданныеМостаТоррента { БайтыМетаданных содержимое; };
РезультатГраницыМоста выполнить_создание_метаданных(
    ВходМостаТоррента const* вход, МетаданныеМостаТоррента** адрес, ПроизводительМетаданных производитель,
    void* контекст_производителя) noexcept {
    return выполнить_без_исключений([&] {
        if (!вход || !адрес || *адрес || !производитель) throw std::invalid_argument("неверный адрес входа или результата");
        auto параметры = *вход;
        if (!параметры.операция || !параметры.хэш || параметры.длина_хэша != 32
            || параметры.максимум_метаданных == 0 || параметры.длина_части < 16384
            || параметры.длина_части > 128 * 1024 * 1024
            || (параметры.длина_части & (параметры.длина_части - 1)) != 0)
            throw std::invalid_argument("неверные ограничения или хэш входа");
        if (производитель == произвести_библиотечные_метаданные)
            static_cast<void>(рассчитать_бюджет_метаданных(параметры));
        std::array<uint8_t, 32> хэш{};
        std::memcpy(хэш.data(), параметры.хэш, хэш.size());
        проверить_отмену_метаданных(параметры);
        auto снимок = создать_снимок_файла(параметры.исходник, параметры.каталог,
            параметры.имя, параметры.длина_имени, параметры.размер, параметры.максимум_файла,
            хэш, параметры.операция, ПримитивыСнимка{параметры.контекст, nullptr, nullptr, параметры.проверка_отмены});
        auto результат = std::make_unique<МетаданныеМостаТоррента>();
        результат->содержимое = производитель(контекст_производителя, *снимок);
        проверить_отмену_метаданных(параметры);
        auto const& содержимое = результат->содержимое;
        if (содержимое.данные.empty() || содержимое.данные.size() > параметры.максимум_метаданных
            || !шестнадцатеричный_хэш(содержимое.хэш_первой_версии, 40)
            || !шестнадцатеричный_хэш(содержимое.хэш_второй_версии, 64))
            throw std::runtime_error("неверные байтовые границы результата");
        снимок->удалить_с_проверкой();
        проверить_отмену_метаданных(параметры);
        *адрес = результат.release();
    });
}
extern "C" РезультатГраницыМоста создать_метаданные_торрента(
    ВходМостаТоррента const* вход, МетаданныеМостаТоррента** адрес) {
    РезультатГраницыМоста результат{};
    auto граница = выполнить_без_исключений([&] {
        if (!вход || !адрес || *адрес || !вход->хэш
            || вход->длина_хэша != 32)
            throw std::invalid_argument("неверный вход производственного провайдера");
        КонтекстПроизводственногоПровайдера контекст;
        контекст.вход = *вход;
        std::memcpy(контекст.хэш.data(), вход->хэш, контекст.хэш.size());
        контекст.вход.хэш = контекст.хэш.data();
        результат = выполнить_создание_метаданных(
            &контекст.вход, адрес, произвести_библиотечные_метаданные,
            &контекст);
    });
    return граница.код == УспехГраницыМоста ? результат : граница;
}

#pragma once
#include <exception>
#include <new>

extern "C" {
#include "include/ГраницаМоста.h"
}

struct ОтменаОперацииМоста {};

inline void сохранить_сообщение_ошибки(
    РезультатГраницыМоста& результат, char const* сообщение) noexcept {
    if (сообщение == nullptr) сообщение = "неизвестная ошибка C++";
    unsigned номер = 0;
    while (номер + 1 < sizeof(результат.сообщение) && сообщение[номер] != '\0') {
        результат.сообщение[номер] = сообщение[номер];
        ++номер;
    }
    результат.сообщение[номер] = '\0';
}

template <class Действие>
РезультатГраницыМоста выполнить_без_исключений(Действие&& действие) noexcept {
    РезультатГраницыМоста результат{};
    try {
        действие();
    } catch (ОтменаОперацииМоста const&) {
        результат.код = ОтменаГраницыМоста;
        сохранить_сообщение_ошибки(результат, "операция отменена");
    } catch (std::bad_alloc const&) {
        результат.код = ОшибкаПамятиГраницыМоста;
        сохранить_сообщение_ошибки(результат, "недостаточно памяти");
    } catch (std::exception const& ошибка) {
        результат.код = ОшибкаГраницыМоста;
        сохранить_сообщение_ошибки(результат, ошибка.what());
    } catch (...) {
        результат.код = ОшибкаГраницыМоста;
        сохранить_сообщение_ошибки(результат, "неизвестное исключение C++");
    }
    return результат;
}

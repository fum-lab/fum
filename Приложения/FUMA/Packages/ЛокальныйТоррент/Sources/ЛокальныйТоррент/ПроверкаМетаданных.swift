public enum ПроверкаМетаданныхТоррента {
    public static func проверить(_ метаданные: СозданныеМетаданныеТоррента,
                                 имя: String, размер: UInt64,
                                 ограничения: ОграниченияПодготовкиТоррента) throws {
        func требовать(_ условие: Bool) throws {
            if !условие { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }
        }
        let данные = метаданные.бенкодированныеДанные
        try требовать(UInt64(данные.count) <= ограничения.максимумБайтМетаданных
                      && размер > 0 && размер <= ограничения.максимумБайтФайла && размер <= UInt64(Int64.max)
                      && !имя.isEmpty && !имя.contains("/") && !имя.contains("\0") && имя != "." && имя != "..")
        var разбор = РазборБенкода(байты: Array(данные))
        let корень = try разбор.узел(глубина: 0)
        try требовать(разбор.позиция == данные.count)
        let словарь = try корень.словарь()
        guard let информация = словарь[Data("info".utf8)], let слои = словарь[Data("piece layers".utf8)] else {
            throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные
        }
        let поля = try информация.словарь()
        try требовать(поля[Data("files".utf8)] == nil && поля[Data("attr".utf8)] == nil
                      && поля[Data("symlink path".utf8)] == nil)
        let длина = ограничения.длинаЧастиБайт
        try требовать(try поля.поле("meta version").целое() == 2)
        try требовать(try поля.поле("length").целое() == Int64(размер))
        try требовать(try поля.поле("piece length").целое() == Int64(длина))
        try требовать(try поля.поле("name").данные() == Data(имя.utf8))
        let числоЧастей = (размер - 1) / UInt64(длина) + 1
        try требовать(числоЧастей <= UInt64(Int.max / 32))
        let части = try поля.поле("pieces").данные()
        try требовать(части.count == Int(числоЧастей) * 20)
        let дерево = try поля.поле("file tree").словарь()
        try требовать(дерево.count == 1)
        guard let файл = дерево[Data(имя.utf8)] else { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }
        let ветви = try файл.словарь()
        try требовать(ветви.count == 1)
        guard let лист = ветви[Data()] else { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }
        let описание = try лист.словарь()
        try требовать(описание.count == 2 && описание[Data("attr".utf8)] == nil)
        try требовать(try описание.поле("length").целое() == Int64(размер))
        let корневойХэш = try описание.поле("pieces root").данные()
        try требовать(корневойХэш.count == 32 && корневойХэш.contains { $0 != 0 })
        let словарьСлоёв = try слои.словарь()
        if размер <= UInt64(длина) {
            try требовать(словарьСлоёв.isEmpty)
        } else {
            try требовать(словарьСлоёв.count == 1)
            guard let слой = словарьСлоёв[корневойХэш] else { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }
            let хэши = try слой.данные()
            try требовать(хэши.count == Int(числоЧастей) * 32)
            var нулевойХэш = Data(repeating: 0, count: 32)
            var размерУзла = 16384
            while размерУзла < длина {
                нулевойХэш = Data(SHA256.hash(data: нулевойХэш + нулевойХэш)); размерУзла *= 2
            }
            var узлы = stride(from: 0, to: хэши.count, by: 32).map { хэши.subdata(in: $0..<($0 + 32)) }
            var мощность = 1
            while мощность < узлы.count { мощность *= 2 }
            узлы += Array(repeating: нулевойХэш, count: мощность - узлы.count)
            while узлы.count > 1 {
                узлы = stride(from: 0, to: узлы.count, by: 2).map { Data(SHA256.hash(data: узлы[$0] + узлы[$0 + 1])) }
            }
            try требовать(узлы[0] == корневойХэш)
        }
        let точныеБайты = данные.subdata(in: информация.диапазон)
        func шестнадцатеричный(_ хэш: Data) -> String { хэш.map { String(format: "%02x", $0) }.joined() }
        try требовать(метаданные.хэшиИнформации.хэшВерсии1 == шестнадцатеричный(Data(Insecure.SHA1.hash(data: точныеБайты)))
                      && метаданные.хэшиИнформации.хэшВерсии2 == шестнадцатеричный(Data(SHA256.hash(data: точныеБайты))))
    }
}

struct УзелБенкода {
    indirect enum Значение {
        case число(Int64)
        case строка(Data)
        case список([УзелБенкода])
        case словарь([Data: УзелБенкода])
    }
    let значение: Значение
    let диапазон: Range<Int>
    func целое() throws -> Int64 {
        guard case .число(let число) = значение else { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }; return число
    }
    func данные() throws -> Data {
        guard case .строка(let данные) = значение else { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }; return данные
    }
    func словарь() throws -> [Data: УзелБенкода] {
        guard case .словарь(let словарь) = значение else { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }; return словарь
    }
}

private extension Dictionary where Key == Data, Value == УзелБенкода {
    func поле(_ имя: String) throws -> УзелБенкода {
        guard let узел = self[Data(имя.utf8)] else { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }; return узел
    }
}

struct РазборБенкода {
    let байты: [UInt8]
    var позиция = 0
    var числоУзлов = 0
    mutating func отказ() throws -> Never { throw ОшибкаПроверкиМетаданных.недостоверныеМетаданные }
    mutating func десятичное(до разделитель: UInt8) throws -> UInt64 {
        let начало = позиция
        var число: UInt64 = 0
        while позиция < байты.count && байты[позиция] != разделитель {
            let байт = байты[позиция]
            guard байт >= 48 && байт <= 57 else { try отказ() }
            let цифра = UInt64(байт - 48)
            guard число <= (UInt64.max - цифра) / 10 else { try отказ() }
            число = число * 10 + цифра; позиция += 1
        }
        guard позиция < байты.count && позиция > начало
            && (позиция - начало == 1 || байты[начало] != 48) else { try отказ() }
        позиция += 1; return число
    }
    mutating func узел(глубина: Int, максимумСтроки: UInt64? = nil) throws -> УзелБенкода {
        guard глубина <= 8 && позиция < байты.count && числоУзлов < 256 else { try отказ() }
        числоУзлов += 1
        let начало = позиция
        let значение: УзелБенкода.Значение
        switch байты[позиция] {
        case 105:
            позиция += 1
            guard позиция < байты.count else { try отказ() }
            let отрицательное = байты[позиция] == 45
            if отрицательное { позиция += 1 }
            let число = try десятичное(до: 101)
            guard число <= UInt64(Int64.max) + (отрицательное ? 1 : 0)
                && (!отрицательное || число != 0) else { try отказ() }
            значение = .число(отрицательное ? (число == UInt64(Int64.max) + 1 ? Int64.min : -Int64(число)) : Int64(число))
        case 108:
            позиция += 1; var список: [УзелБенкода] = []
            while позиция < байты.count && байты[позиция] != 101 { список.append(try узел(глубина: глубина + 1)) }
            guard позиция < байты.count else { try отказ() }; позиция += 1; значение = .список(список)
        case 100:
            позиция += 1; var словарь: [Data: УзелБенкода] = [:]; var предыдущий: Data?
            while позиция < байты.count && байты[позиция] != 101 {
                let ключ = try узел(глубина: глубина + 1, максимумСтроки: 1024).данные()
                guard ключ.count <= 1024 && (предыдущий == nil || предыдущий!.lexicographicallyPrecedes(ключ)) else { try отказ() }
                предыдущий = ключ; словарь[ключ] = try узел(глубина: глубина + 1)
            }
            guard позиция < байты.count else { try отказ() }; позиция += 1; значение = .словарь(словарь)
        case 48...57:
            let длина = try десятичное(до: 58)
            guard длина <= UInt64(байты.count - позиция) && (максимумСтроки == nil || длина <= максимумСтроки!) else { try отказ() }
            значение = .строка(Data(байты[позиция..<(позиция + Int(длина))])); позиция += Int(длина)
        default: try отказ()
        }
        return УзелБенкода(значение: значение, диапазон: начало..<позиция)
    }
}

public enum ЭтапПодготовкиТоррента: String, Sendable, Equatable {
    case хэшИсточника
    case частиМетаданных
    case проверкаИсточника
}

public struct ХодПодготовкиТоррента: Sendable, Equatable {
    public let этап: ЭтапПодготовкиТоррента
    public let завершено: UInt64
    public let всего: UInt64

    public init(этап: ЭтапПодготовкиТоррента, завершено: UInt64, всего: UInt64) {
        self.этап = этап
        self.завершено = завершено
        self.всего = всего
    }
}

public struct ВыборЛокальногоФайла: Sendable, Equatable {
    public let адрес: URL

    public init(адрес: URL) throws {
        guard адрес.isFileURL else { throw ОшибкаПодготовкиТоррента.выбранныйОбъектНеЯвляетсяЛокальнымФайлом }
        self.адрес = адрес.standardizedFileURL
    }
}

public struct ОграниченияПодготовкиТоррента: Sendable, Equatable {
    public static let минимальнаяДлинаЧастиБайт = 16 * 1024
    public static let максимальнаяДлинаЧастиБайт = 128 * 1024 * 1024

    public let максимумБайтФайла: UInt64
    public let длинаЧастиБайт: Int
    public let максимумБайтМетаданных: UInt64

    public init(максимумБайтФайла: UInt64, длинаЧастиБайт: Int, максимумБайтМетаданных: UInt64) throws {
        guard максимумБайтФайла > 0 else { throw ОшибкаПодготовкиТоррента.недопустимоеОграничениеФайла }
        guard максимумБайтМетаданных > 0 else { throw ОшибкаПодготовкиТоррента.недопустимоеОграничениеМетаданных }
        guard длинаЧастиБайт >= Self.минимальнаяДлинаЧастиБайт,
              длинаЧастиБайт <= Self.максимальнаяДлинаЧастиБайт,
              длинаЧастиБайт.nonzeroBitCount == 1 else {
            throw ОшибкаПодготовкиТоррента.недопустимаяДлинаЧасти(длинаЧастиБайт)
        }
        self.максимумБайтФайла = максимумБайтФайла
        self.длинаЧастиБайт = длинаЧастиБайт
        self.максимумБайтМетаданных = максимумБайтМетаданных
    }
}

public struct ХэшиИнформацииТоррента: Sendable, Equatable {
    public let хэшВерсии1: String?
    public let хэшВерсии2: String?

    public init(хэшВерсии1: String?, хэшВерсии2: String?) throws {
        guard хэшВерсии1 != nil || хэшВерсии2 != nil else { throw ОшибкаПодготовкиТоррента.отсутствуетХэшИнформации }
        if let хэшВерсии1, !Self.являетсяШестнадцатеричным(хэшВерсии1, длина: 40) { throw ОшибкаПодготовкиТоррента.недопустимыйХэшИнформации }
        if let хэшВерсии2, !Self.являетсяШестнадцатеричным(хэшВерсии2, длина: 64) { throw ОшибкаПодготовкиТоррента.недопустимыйХэшИнформации }
        self.хэшВерсии1 = хэшВерсии1
        self.хэшВерсии2 = хэшВерсии2
    }

    private static func являетсяШестнадцатеричным(_ строкаШестнадцатеричногоЧисла: String, длина: Int) -> Bool {
        строкаШестнадцатеричногоЧисла.utf8.count == длина && строкаШестнадцатеричногоЧисла.utf8.allSatisfy {
            ($0 >= 48 && $0 <= 57) || ($0 >= 97 && $0 <= 102)
        }
    }
}

public struct СозданныеМетаданныеТоррента: Sendable, Equatable {
    public let бенкодированныеДанные: Data
    public let хэшиИнформации: ХэшиИнформацииТоррента

    public init(бенкодированныеДанные: Data, хэшиИнформации: ХэшиИнформацииТоррента) throws {
        guard !бенкодированныеДанные.isEmpty else { throw ОшибкаПодготовкиТоррента.пустыеМетаданные }
        self.бенкодированныеДанные = бенкодированныеДанные
        self.хэшиИнформации = хэшиИнформации
    }
}

public struct АртефактЛокальногоТоррента: Sendable, Equatable {
    public let имяФайла: String
    public let размерФайла: UInt64
    public let хэшСодержимого: String
    public let длинаЧастиБайт: Int
    public let хэшиИнформации: ХэшиИнформацииТоррента
    public let бенкодированныеМетаданные: Data
}

public enum ОшибкаПодготовкиТоррента: Error, Sendable, Equatable {
    case выбранныйОбъектНеЯвляетсяЛокальнымФайлом
    case источникНедоступен(код: Int32)
    case источникНеОбычныйФайл
    case пустойФайл
    case недопустимоеОграничениеФайла
    case недопустимоеОграничениеМетаданных
    case недопустимаяДлинаЧасти(Int)
    case файлПревышаетОграничение(UInt64, UInt64)
    case метаданныеПревышаютОграничение(UInt64, UInt64)
    case источникИзменилсяПриПодготовке
    case отсутствуетХэшИнформации
    case недопустимыйХэшИнформации
    case пустыеМетаданные
    case сбойОбработчика(String)
    case отменено
}

public final class ОтменаПодготовкиТоррента: @unchecked Sendable {
    private let синхронизатор = NSLock()
    private var отменено = false

    public init() {}

    public func отменить() {
        синхронизатор.lock()
        отменено = true
        синхронизатор.unlock()
    }

    public var запрошенаОтмена: Bool {
        синхронизатор.lock()
        defer { синхронизатор.unlock() }
        return отменено
    }

    public func проверитьОтмену() throws {
        if запрошенаОтмена { throw ОшибкаПодготовкиТоррента.отменено }
    }
}

public protocol ОбработчикМетаданныхТоррента: Sendable {
    func создать(
        адресФайла: URL,
        имяФайла: String,
        размерФайла: UInt64,
        ожидаемыйХэшСодержимого: String,
        ограничения: ОграниченияПодготовкиТоррента,
        отмена: ОтменаПодготовкиТоррента,
        ход: @escaping @Sendable (ХодПодготовкиТоррента) -> Void
    ) async throws -> СозданныеМетаданныеТоррента
}

public struct АдаптерЛокальногоТоррента: Sendable {
    private let обработчик: any ОбработчикМетаданныхТоррента

    public init(обработчик: any ОбработчикМетаданныхТоррента) {
        self.обработчик = обработчик
    }

    public func подготовить(
        файл: ВыборЛокальногоФайла,
        ограничения: ОграниченияПодготовкиТоррента,
        ход: @escaping @Sendable (ХодПодготовкиТоррента) -> Void = { _ in }
    ) async throws -> АртефактЛокальногоТоррента {
        let отмена = ОтменаПодготовкиТоррента()
        return try await withTaskCancellationHandler {
            do {
                try отмена.проверитьОтмену()
                let начальнаяМетка = try await Task.detached(priority: .utility) {
                    try Self.проверитьСвойства(файл.адрес, ограничения: ограничения)
                }.value
                let начальныйХэш = try await Task.detached(priority: .utility) {
                    try Self.вычислитьХэш(файл.адрес, ожидаемыйРазмер: начальнаяМетка.размер, этап: .хэшИсточника,
                                   отмена: отмена, ход: ход)
                }.value

                try отмена.проверитьОтмену()
                let метаданные = try await обработчик.создать(
                    адресФайла: файл.адрес,
                    имяФайла: файл.адрес.lastPathComponent,
                    размерФайла: начальнаяМетка.размер,
                    ожидаемыйХэшСодержимого: начальныйХэш.хэш,
                    ограничения: ограничения,
                    отмена: отмена,
                    ход: ход
                )

                try отмена.проверитьОтмену()
                let итоговыйХэш = try await Task.detached(priority: .utility) {
                    try Self.вычислитьХэш(файл.адрес, ожидаемыйРазмер: начальнаяМетка.размер, этап: .проверкаИсточника,
                                   отмена: отмена, ход: ход)
                }.value

                guard начальнаяМетка == итоговыйХэш.метка,
                      начальныйХэш.хэш == итоговыйХэш.хэш else {
                    throw ОшибкаПодготовкиТоррента.источникИзменилсяПриПодготовке
                }
                guard UInt64(метаданные.бенкодированныеДанные.count) <= ограничения.максимумБайтМетаданных else {
                    throw ОшибкаПодготовкиТоррента.метаданныеПревышаютОграничение(
                        UInt64(метаданные.бенкодированныеДанные.count), ограничения.максимумБайтМетаданных
                    )
                }
                try ПроверкаМетаданныхТоррента.проверить(метаданные,
                    имя: файл.адрес.lastPathComponent, размер: начальнаяМетка.размер, ограничения: ограничения)
                try отмена.проверитьОтмену()
                return АртефактЛокальногоТоррента(
                    имяФайла: файл.адрес.lastPathComponent,
                    размерФайла: начальнаяМетка.размер,
                    хэшСодержимого: начальныйХэш.хэш,
                    длинаЧастиБайт: ограничения.длинаЧастиБайт,
                    хэшиИнформации: метаданные.хэшиИнформации,
                    бенкодированныеМетаданные: метаданные.бенкодированныеДанные
                )
            } catch is CancellationError {
                throw ОшибкаПодготовкиТоррента.отменено
            }
        } onCancel: {
            отмена.отменить()
        }
    }

    private struct МеткаФайла: Equatable, Sendable {
        let устройство: UInt64
        let номерУзлаФайла: UInt64
        let размер: UInt64
        let секундыПравки: Int64
        let наносекундыПравки: Int64
        let секундыСмены: Int64
        let наносекундыСмены: Int64
    }

    private struct ХэшФайла: Sendable {
        let метка: МеткаФайла
        let хэш: String
    }

    private static func проверитьСвойства(_ адрес: URL, ограничения: ОграниченияПодготовкиТоррента) throws -> МеткаФайла {
        let дескриптор = try открытьОбычныйФайл(адрес)
        defer { Darwin.close(дескриптор) }
        let метка = try снятьОтпечатокФайла(дескриптор)
        guard метка.размер > 0 else { throw ОшибкаПодготовкиТоррента.пустойФайл }
        guard метка.размер <= ограничения.максимумБайтФайла else {
            throw ОшибкаПодготовкиТоррента.файлПревышаетОграничение(метка.размер, ограничения.максимумБайтФайла)
        }

        let части = (метка.размер - 1) / UInt64(ограничения.длинаЧастиБайт) + 1
        let оценка = части.multipliedReportingOverflow(by: 64)
        let общаяОценка = оценка.partialValue.addingReportingOverflow(4096)
        guard !оценка.overflow, !общаяОценка.overflow,
              общаяОценка.partialValue <= ограничения.максимумБайтМетаданных else {
            let требуемыйРазмер = оценка.overflow || общаяОценка.overflow ? UInt64.max : общаяОценка.partialValue
            throw ОшибкаПодготовкиТоррента.метаданныеПревышаютОграничение(
                требуемыйРазмер, ограничения.максимумБайтМетаданных
            )
        }
        return метка
    }

    private static func вычислитьХэш(
        _ адрес: URL,
        ожидаемыйРазмер: UInt64,
        этап: ЭтапПодготовкиТоррента,
        отмена: ОтменаПодготовкиТоррента,
        ход: @Sendable (ХодПодготовкиТоррента) -> Void
    ) throws -> ХэшФайла {
        let дескриптор = try открытьОбычныйФайл(адрес)
        defer { Darwin.close(дескриптор) }
        let начальнаяМетка = try снятьОтпечатокФайла(дескриптор)
        guard начальнаяМетка.размер > 0 else { throw ОшибкаПодготовкиТоррента.пустойФайл }
        guard начальнаяМетка.размер == ожидаемыйРазмер else { throw ОшибкаПодготовкиТоррента.источникИзменилсяПриПодготовке }

        var вычислительХэша = SHA256()
        var буфер = [UInt8](repeating: 0, count: 1024 * 1024)
        var завершено: UInt64 = 0
        while true {
            try отмена.проверитьОтмену()
            let осталосьБайт = ожидаемыйРазмер - завершено
            let пределЧтения = осталосьБайт == 0 ? 1 : Int(min(UInt64(буфер.count), осталосьБайт))
            let прочитаноБайт = буфер.withUnsafeMutableBytes { байты in
                Darwin.read(дескриптор, байты.baseAddress, пределЧтения)
            }
            if прочитаноБайт < 0 {
                if errno == EINTR { continue }
                throw ОшибкаПодготовкиТоррента.источникНедоступен(код: errno)
            }
            if прочитаноБайт == 0 { break }
            guard UInt64(прочитаноБайт) <= осталосьБайт else {
                throw ОшибкаПодготовкиТоррента.источникИзменилсяПриПодготовке
            }
            вычислительХэша.update(data: Data(буфер.prefix(прочитаноБайт)))
            завершено += UInt64(прочитаноБайт)
            ход(ХодПодготовкиТоррента(этап: этап, завершено: завершено, всего: ожидаемыйРазмер))
        }

        let итоговаяМетка = try снятьОтпечатокФайла(дескриптор)
        guard завершено == ожидаемыйРазмер, начальнаяМетка == итоговаяМетка else {
            throw ОшибкаПодготовкиТоррента.источникИзменилсяПриПодготовке
        }
        let вычислитьХэш = вычислительХэша.finalize().map { String(format: "%02x", $0) }.joined()
        return ХэшФайла(метка: итоговаяМетка, хэш: вычислитьХэш)
    }

    private static func открытьОбычныйФайл(_ адрес: URL) throws -> Int32 {
        let дескриптор = Darwin.open(адрес.path, O_RDONLY | O_CLOEXEC | O_NOFOLLOW | O_NONBLOCK)
        guard дескриптор >= 0 else { throw ОшибкаПодготовкиТоррента.источникНедоступен(код: errno) }
        var состояниеФайла = stat()
        guard Darwin.fstat(дескриптор, &состояниеФайла) == 0 else {
            let код = errno
            Darwin.close(дескриптор)
            throw ОшибкаПодготовкиТоррента.источникНедоступен(код: код)
        }
        guard (состояниеФайла.st_mode & mode_t(S_IFMT)) == mode_t(S_IFREG) else {
            Darwin.close(дескриптор)
            throw ОшибкаПодготовкиТоррента.источникНеОбычныйФайл
        }
        return дескриптор
    }

    private static func снятьОтпечатокФайла(_ дескриптор: Int32) throws -> МеткаФайла {
        var состояниеФайла = stat()
        guard Darwin.fstat(дескриптор, &состояниеФайла) == 0 else {
            throw ОшибкаПодготовкиТоррента.источникНедоступен(код: errno)
        }
        guard состояниеФайла.st_size >= 0 else { throw ОшибкаПодготовкиТоррента.источникНедоступен(код: EOVERFLOW) }
        return МеткаФайла(
            устройство: UInt64(состояниеФайла.st_dev),
            номерУзлаФайла: UInt64(состояниеФайла.st_ino),
            размер: UInt64(состояниеФайла.st_size),
            секундыПравки: Int64(состояниеФайла.st_mtimespec.tv_sec),
            наносекундыПравки: Int64(состояниеФайла.st_mtimespec.tv_nsec),
            секундыСмены: Int64(состояниеФайла.st_ctimespec.tv_sec),
            наносекундыСмены: Int64(состояниеФайла.st_ctimespec.tv_nsec)
        )
    }
}

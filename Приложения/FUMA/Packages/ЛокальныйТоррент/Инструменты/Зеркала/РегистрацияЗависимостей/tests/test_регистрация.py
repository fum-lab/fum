        сам.assertTrue(any("граница" in ошибка for ошибка in ошибки), ошибки)
        сам.assertEqual(пользовательские, метаданные.read_bytes())
        сам.assertEqual(до, сам.снимок())
        сам.assertFalse((сам.дерево / getattr(сам.описание, "path")).exists())


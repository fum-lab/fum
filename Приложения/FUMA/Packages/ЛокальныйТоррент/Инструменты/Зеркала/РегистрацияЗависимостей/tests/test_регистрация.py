        сам.подготовить()
        до = сам.снимок()
        метаданные = сам.дерево / ".gitmodules"
        пользовательские = "# Поздняя пользовательская запись\n".encode()
        настоящий = регистратор.проверить_исполнителя
        вызовы = []
        def проверить(*аргументы):
            результат = настоящий(*аргументы)
            вызовы.append(True)
            if len(вызовы) == 2:
                метаданные.write_bytes(пользовательские)

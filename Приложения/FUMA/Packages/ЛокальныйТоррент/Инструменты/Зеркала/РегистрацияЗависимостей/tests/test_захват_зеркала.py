"""Открытые Git-фикстуры захвата конечного зеркала, без сети."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import stat
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import захват_зеркала


class ЗахватЗеркала(unittest.TestCase):
    def setUp(сам):
        временный = tempfile.TemporaryDirectory(prefix="fum-mirror-capture-")
        сам.addCleanup(временный.cleanup)
        сам.основание = Path(временный.name).resolve()
        сам.корень = сам.основание / "источник"
        сам.корень.mkdir()
        сам.гит("init", "-q")
        (сам.корень / "модуль.py").write_text("значение = 7\n")
        (сам.корень / "ссылка.py").symlink_to("модуль.py")
        сам.гит("add", ".")
        сам.гит("commit", "-qm", "Открытая фикстура зеркала")
        сам.коммит = сам.гит("rev-parse", "HEAD").decode().strip()

    def гит(сам, *аргументы):
        return subprocess.check_output(["git", "-c", "user.name=FUM Test",
            "-c", "user.email=test@example.invalid", "-c", "core.hooksPath=/dev/null",
            "-C", str(сам.корень), *аргументы], stderr=subprocess.PIPE)

    def test_два_совпадающих_пути_не_создают_зеркало(сам):
        with сам.assertRaisesRegex(ValueError, "повтор"):
            захват_зеркала.снять(сам.корень, сам.коммит, ["модуль.py", "модуль.py"])

    def test_символическая_ссылка_из_гит_не_считается_исходником(сам):
        with сам.assertRaisesRegex(ValueError, "обычн"):
            захват_зеркала.снять(сам.корень, сам.коммит, ["ссылка.py"])

    def test_замещающие_ссылки_не_подменяют_дерево_закреплённого_коммита(сам):
        исходные = (сам.корень / "модуль.py").read_bytes()
        (сам.корень / "модуль.py").write_text("значение = 8\n")
        сам.гит("add", ".")
        сам.гит("commit", "-qm", "Другое дерево")
        новый = сам.гит("rev-parse", "HEAD").decode().strip()
        сам.гит("replace", сам.коммит, новый)
        план = захват_зеркала.снять(сам.корень, сам.коммит, ["модуль.py"])
        сам.assertEqual(hashlib.sha256(исходные).hexdigest(), план["файлы"][0]["sha256"])

    def test_подкаталог_не_подменяет_корень_репозитория(сам):
        вложенный = сам.корень / "подкаталог"
        вложенный.mkdir()
        (вложенный / "модуль.py").write_text("значение = 9\n")
        сам.гит("add", ".")
        сам.гит("commit", "-qm", "Вложенный файл")
        коммит = сам.гит("rev-parse", "HEAD").decode().strip()
        with сам.assertRaisesRegex(ValueError, "корень"):
            захват_зеркала.снять(вложенный, коммит, ["модуль.py"])

    def test_коллизия_компонента_каталога_отказывает(сам):
        for имя, файл in [("Верхний", "первый.py"), ("ВЕРХНИЙ", "второй.py")]:
            каталог = сам.корень / имя
            каталог.mkdir(exist_ok=True)
            (каталог / файл).write_text("значение = 1\n")
        # Индекс может хранить разные регистры каталогов и на нечувствительном томе.
        объект = сам.гит("rev-parse", сам.коммит + ":модуль.py").decode().strip()
        for имя in ["Верхний/первый.py", "ВЕРХНИЙ/второй.py"]:
            сам.гит("update-index", "--add", "--cacheinfo", "100644," + объект + "," + имя)
        сам.гит("commit", "-qm", "Коллизия компонентов")
        коммит = сам.гит("rev-parse", "HEAD").decode().strip()
        with сам.assertRaisesRegex(ValueError, "коллиз"):
            захват_зеркала.снять(сам.корень, коммит, ["Верхний/первый.py", "ВЕРХНИЙ/второй.py"])

    def test_детерминированный_план_сохраняет_объект_и_байты(сам):
        план = захват_зеркала.снять(сам.корень, сам.коммит, ["модуль.py"])
        сам.assertEqual(план, захват_зеркала.снять(сам.корень, сам.коммит, ["модуль.py"]))
        запись = план["файлы"][0]
        байты = (сам.корень / "модуль.py").read_bytes()
        сам.assertEqual("100644", запись["режим"])
        сам.assertEqual(сам.гит("rev-parse", сам.коммит + ":модуль.py").decode().strip(), запись["blob"])
        сам.assertEqual(hashlib.sha256(байты).hexdigest(), запись["sha256"])
        сам.assertEqual(len(байты), запись["байты"])

    def test_подмена_плана_не_создаёт_назначение(сам):
        план = захват_зеркала.снять(сам.корень, сам.коммит, ["модуль.py"])
        хэш = hashlib.sha256(захват_зеркала.байты_плана(план)).hexdigest()
        план["файлы"][0]["sha256"] = "0" * 64
        назначение = сам.основание / "зеркало"
        with сам.assertRaises(ValueError):
            захват_зеркала.сохранить(сам.корень, план, назначение, хэш)
        сам.assertFalse(назначение.exists())

    def test_тип_размера_не_подменяется_равным_числом(сам):
        (сам.корень / "модуль.py").write_bytes(b"x")
        сам.гит("add", ".")
        сам.гит("commit", "-qm", "Один байт")
        коммит = сам.гит("rev-parse", "HEAD").decode().strip()
        for подмена in [True, 1.0]:
            план = захват_зеркала.снять(сам.корень, коммит, ["модуль.py"])
            план["файлы"][0]["байты"] = подмена
            хэш = hashlib.sha256(захват_зеркала.байты_плана(план)).hexdigest()
            назначение = сам.основание / ("тип-" + str(type(подмена).__name__))
            with сам.assertRaises(ValueError):
                захват_зеркала.сохранить(сам.корень, план, назначение, хэш)
            сам.assertFalse(назначение.exists())

    def test_ошибка_после_переименования_сохраняет_публикацию_и_повторяет_синхронизацию_каталога(сам):
        план = захват_зеркала.снять(сам.корень, сам.коммит, ["модуль.py"])
        хэш = hashlib.sha256(захват_зеркала.байты_плана(план)).hexdigest()
        назначение = сам.основание / "синхронизация"
        исходная = os.fsync
        def отказать(дескриптор):
            состояние = os.fstat(дескриптор)
            if stat.S_ISDIR(состояние.st_mode) and состояние.st_ino == сам.основание.stat().st_ino:
                raise OSError(5, "EIO родителя")
            return исходная(дескриптор)
        with mock.patch.object(os, "fsync", new=отказать):
            with сам.assertRaises(OSError) as отказ:
                захват_зеркала.сохранить(сам.корень, план, назначение, хэш)
        сам.assertTrue(назначение.is_dir())
        сам.assertTrue(any("rename выполнен" in пометка and "синхронизация родителя" in пометка
                           for пометка in getattr(отказ.exception, "__notes__", [])))
        вызовы = []
        def сохранить_вызов(дескриптор):
            состояние = os.fstat(дескриптор)
            if stat.S_ISDIR(состояние.st_mode):
                вызовы.append((состояние.st_dev, состояние.st_ino))
            return исходная(дескриптор)
        with mock.patch.object(os, "fsync", new=сохранить_вызов):
            захват_зеркала.сохранить(сам.корень, план, назначение, хэш)
        родитель = сам.основание.stat()
        сам.assertIn((родитель.st_dev, родитель.st_ino), вызовы)

    def test_отказ_записи_не_публикует_частичное_зеркало(сам):
        план = захват_зеркала.снять(сам.корень, сам.коммит, ["модуль.py"])
        хэш = hashlib.sha256(захват_зеркала.байты_плана(план)).hexdigest()
        назначение = сам.основание / "зеркало"
        with mock.patch.object(Path, "write_bytes", side_effect=OSError("Отказ носителя")):
            with сам.assertRaises(OSError):
                захват_зеркала.сохранить(сам.корень, план, назначение, хэш)
        сам.assertFalse(назначение.exists())
        сам.assertEqual([], list(сам.основание.glob(".fum-mirror-capture-*")))

    def test_повтор_сверяет_байты_без_перезаписи(сам):
        план = захват_зеркала.снять(сам.корень, сам.коммит, ["модуль.py"])
        хэш = hashlib.sha256(захват_зеркала.байты_плана(план)).hexdigest()
        назначение = сам.основание / "зеркало"
        захват_зеркала.сохранить(сам.корень, план, назначение, хэш)
        до = {п.relative_to(назначение): (п.read_bytes(), п.stat().st_mtime_ns,
              п.stat().st_dev, п.stat().st_ino, stat.S_IMODE(п.stat().st_mode))
              for п in назначение.rglob("*") if п.is_file()}
        захват_зеркала.сохранить(сам.корень, план, назначение, хэш)
        сам.assertEqual(до, {п.relative_to(назначение): (п.read_bytes(), п.stat().st_mtime_ns,
              п.stat().st_dev, п.stat().st_ino, stat.S_IMODE(п.stat().st_mode))
              for п in назначение.rglob("*") if п.is_file()})
        источник = назначение / "Источники" / сам.коммит / "модуль.py"
        источник.write_bytes("Подмена".encode())
        with сам.assertRaises(ValueError):
            захват_зеркала.сохранить(сам.корень, план, назначение, хэш)
        сам.assertEqual("Подмена".encode(), источник.read_bytes())


if __name__ == "__main__":
    unittest.main()

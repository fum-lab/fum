"""Проверить зеркальную Swift-сборку без установки поколения проекции."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import sys
import time


разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
разбор.add_argument("--корень-репозитория", type=Path, required=True)
разбор.add_argument("--без-кеша", action="store_true")
параметры = разбор.parse_args()
корень = параметры.корень_репозитория.resolve(strict=True)
путь = корень / "Приложения/FUMA/Packages/ЛокальныйТоррент/Инструменты/Зеркала/Кандидат/Инструменты/fum-bratislavskaya-proyekciya-pamyati/scripts/братиславская_проекция_памяти.py"
спецификация = importlib.util.spec_from_file_location("независимый_зеркальный_проектор", путь)
модуль = importlib.util.module_from_spec(спецификация)
sys.modules[спецификация.name] = модуль
спецификация.loader.exec_module(модуль)
хэш_кода = hashlib.sha256(путь.read_bytes()).hexdigest()
начало = time.perf_counter_ns()
выбранные = модуль.выбрать_исходники_зеркальной_обёртки(корень)
сведения = модуль.идентичность_зеркальной_обёртки(выбранные)
исходная_граница = модуль.коммит_исходного_зеркала + ":" + модуль.путь_исходной_обёртки
# Полный каталог содержит также SKILL.md/scripts/tests. Проверяется
# синтетическое дерево только выбранных исходников, без записи Git-объектов.
строки = str(модуль.выполнить_команду_контроля_версий(
    корень, "ls-tree", "-r", исходная_граница)).splitlines()
объекты = {}
for строка in строки:
    описание, имя = строка.split("\t", 1)
    режим, вид, объект = описание.split()
    if имя in выбранные:
        if вид != "blob" or (режим, объект) != (выбранные[имя]["режим"], выбранные[имя]["объект"]):
            raise модуль.ОшибкаКонтракта("Исходник зеркальной обёртки отличается от закреплённого Git blob")
        объекты[имя] = (режим, объект)
    elif имя.startswith("Sources/"):
        raise модуль.ОшибкаКонтракта("Закреплённое Sources содержит дополнительный исходник")
if set(объекты) != set(выбранные):
    raise модуль.ОшибкаКонтракта("В закреплённом Git нет всех выбранных исходников")
дерево_исходников = str(модуль.выполнить_команду_контроля_версий(
    корень, "rev-parse", исходная_граница + "/Sources")).strip()
данные_дерева = (объекты["Package.swift"][0].encode("ascii") + b" Package.swift\0"
    + bytes.fromhex(объекты["Package.swift"][1]) + b"40000 Sources\0" + bytes.fromhex(дерево_исходников))
ожидаемое_дерево = hashlib.sha1(b"tree " + str(len(данные_дерева)).encode("ascii")
    + b"\0" + данные_дерева).hexdigest()
if сведения["дерево_обёртки"] != ожидаемое_дерево:
    raise модуль.ОшибкаКонтракта("Вычисленное дерево зеркальной обёртки не совпадает с Git")
try:
    помощники = модуль.подготовить_зеркальные_помощники()
    начало_сборки = time.perf_counter_ns()
    with модуль.подготовить_изолированный_преобразователь(корень, использовать_кэш=not параметры.без_кеша) as (команда, граница):
        подготовка_нс = time.perf_counter_ns() - начало_сборки
        преобразовать = модуль.преобразователь_процесса(команда, граница)
        начало_преобразования = time.perf_counter_ns()
        первый = list(преобразовать(["мост.cpp", "проба.hpp"]))
        первое_нс = time.perf_counter_ns() - начало_преобразования
        начало_преобразования = time.perf_counter_ns()
        второй = list(преобразовать(["мост.cpp", "проба.hpp"]))
        повторное_нс = time.perf_counter_ns() - начало_преобразования
        if первый != ["most.cpp", "proba.hpp"] or второй != первый:
            raise модуль.ОшибкаКонтракта("Независимый Swift-преобразователь вернул другой результат")
    модуль.проверить_границу_зеркальных_помощников()
    if hashlib.sha256(путь.read_bytes()).hexdigest() != хэш_кода:
        raise модуль.ОшибкаКонтракта("Зеркальный проектор изменился во время проверки")
    результат = {"состояние": "подтверждено", "исходники": сведения,
        "хэш_проектора": хэш_кода, "модулей": len(помощники["модули"]),
        "подготовка_сборки_нс": подготовка_нс, "весь_сценарий_нс": time.perf_counter_ns() - начало,
        "кеш_разрешён": not параметры.без_кеша,
        "первое_преобразование_нс": первое_нс, "повторное_преобразование_нс": повторное_нс,
        "результат": первый, "повтор": второй, "поколение_установлено": False}
finally:
    исходная_ошибка = sys.exception()
    try:
        модуль.закрыть_зеркальные_помощники()
    except OSError:
        if исходная_ошибка is None:
            raise
        исходная_ошибка.add_note("Не удалось удалить закрытую копию зеркальных помощников")
print(json.dumps(результат, ensure_ascii=False, sort_keys=True))

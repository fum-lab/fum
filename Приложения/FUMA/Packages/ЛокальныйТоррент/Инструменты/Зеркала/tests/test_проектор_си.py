import copy
import errno
import importlib.util
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock


корень_зеркал = Path(__file__).resolve().parents[1]
корень_кандидата = корень_зеркал / "Кандидат/Инструменты/fum-bratislavskaya-proyekciya-pamyati"
путь_проектора = корень_кандидата / "scripts/братиславская_проекция_памяти.py"
спецификация = importlib.util.spec_from_file_location("зеркальный_проектор", путь_проектора)
модуль = importlib.util.module_from_spec(спецификация)
sys.modules[спецификация.name] = модуль
спецификация.loader.exec_module(модуль)
путь_прежнего = "совместимость/контракт-v2-до-форматов-си-плюс-плюс.json"
прежняя = json.loads((корень_кандидата / путь_прежнего).read_text())
хэш_прежней = "sha256:f8d5cad4c9dac3bb787949b7dbfc00f948b607f2ce7f0ebee5aecebe4bcaf72c"


def новая_политика():
    политика = json.loads((корень_кандидата / "контракт-v2.json").read_text())
    for суффикс in (".cpp", ".hpp"):
        for перечень in (политика["форматы"]["код"]["расширения"],
                         политика["сохраняемые_технические_расширения"]):
            if суффикс not in перечень:
                перечень.append(суффикс)
    return политика


class ТестыЗеркальногоПроектораСи(unittest.TestCase):
    def test_КлассифицируетСиПлюсПлюсССохранениемБайтов(сам):
        политика = json.loads((корень_кандидата / "контракт-v2.json").read_text())
        for суффикс in (".cpp", ".hpp"):
            with сам.subTest(суффикс=суффикс):
                результат = модуль.классифицировать_содержимое(Path("."), "мост" + суффикс,
                    политика, "struct Данные {};\n".encode("utf-8"))
                сам.assertEqual(результат[:2], ("код", "сохранить_байты"))

    def test_СохраняетТехническиеСуффиксы(сам):
        политика = json.loads((корень_кандидата / "контракт-v2.json").read_text())
        for суффикс in (".cpp", ".hpp"):
            сам.assertEqual(модуль.основа_и_расширение("мост" + суффикс, True,
                политика["сохраняемые_технические_расширения"]), ("мост", суффикс))

    def test_ПринимаетТочныйРасширенныйКонтракт(сам):
        сам.assertEqual(модуль.проверить_политику(новая_политика()), новая_политика())

    def test_СогласуетСхемуИКод(сам):
        схема = json.loads((корень_кандидата / "схемы/схема-плана-v2.json").read_text())
        сам.assertEqual(схема["$defs"]["формат_кода"]["properties"]["расширения"]["const"],
            новая_политика()["форматы"]["код"]["расширения"])

    def test_ЧитаетПолныйПрежнийКонтрактВладения(сам):
        сам.assertEqual(модуль.хэш_значения(прежняя), хэш_прежней)
        сам.assertEqual(модуль.политика_для_доказательства_владения(новая_политика(), хэш_прежней), прежняя)
        сам.assertNotEqual(модуль.хэш_значения(новая_политика()), хэш_прежней)

    def test_ОтклоняетНеизвестнуюПолитику(сам):
        with сам.assertRaises(модуль.ОшибкаКонтракта):
            модуль.политика_для_доказательства_владения(новая_политика(), "sha256:" + "0" * 64)

    def test_ОтклоняетПовреждениеПрежнегоПолногоОбъекта(сам):
        повреждённая = copy.deepcopy(прежняя)
        повреждённая["исходная_область"] = "чужой-корень"
        with mock.patch.object(модуль, "безопасно_прочитать_обычный_файл",
                return_value=модуль.канонические_байты(повреждённая)):
            with сам.assertRaises(модуль.ОшибкаКонтракта):
                модуль.политика_для_доказательства_владения(новая_политика(), хэш_прежней)

    def test_ОтклоняетСсылкуВПрежнемКонтракте(сам):
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный).resolve()
            (корень / "scripts").mkdir()
            (корень / "совместимость").mkdir()
            цель = корень / "данные.json"
            цель.write_bytes((корень_кандидата / путь_прежнего).read_bytes())
            (корень / путь_прежнего).symlink_to(цель)
            with mock.patch.object(модуль, "__file__", str(корень / "scripts/проектор.py")):
                with сам.assertRaises(модуль.ОшибкаКонтракта) as свидетельство:
                    модуль.политика_для_доказательства_владения(новая_политика(), хэш_прежней)
                сам.assertIsInstance(свидетельство.exception.__cause__, OSError)
                сам.assertEqual(свидетельство.exception.__cause__.errno, errno.ELOOP)


if __name__ == "__main__":
    unittest.main()

"""Приватный сохраняемый предпросмотр и его проверяемое применение через CLI."""
from __future__ import annotations

import hashlib
import os
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import наполнение_карточки as наполнение
import управляемые_блоки as блоки


def _прочитать(путь, корень):
    путь = наполнение._обычный_внешний_файл(путь, корень)
    return путь, путь.read_bytes()


def _новый_план(путь, корень, байты):
    путь = Path(путь)
    if (not путь.is_absolute() or путь != путь.resolve() or путь.is_relative_to(корень)
            or not путь.parent.is_dir() or os.path.lexists(путь)
            or any(предок.is_symlink() or os.path.lexists(предок / '.git') for предок in путь.parents)):
        raise ValueError('Новый план сохраняется в свободный точный путь вне Git checkout')
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o400)
    with os.fdopen(дескриптор, 'wb') as файл:
        файл.write(байты)
        файл.flush()
        os.fsync(файл.fileno())
    if путь.read_bytes() != байты:
        raise ValueError('Сохранение плана не подтверждено чтением')


def выполнить(режим, корень, путь_входа, путь_плана, ожидаемый_sha256=None):
    корень = Path(корень).resolve()
    путь_входа, байты_входа = _прочитать(путь_входа, корень)
    вход = наполнение.прочитать_json(байты_входа)
    профиль = {}
    if режим == 'наполнение-план':
        план = наполнение.подготовить(корень, вход, профиль=профиль)
        if _прочитать(путь_входа, корень)[1] != байты_входа:
            raise ValueError('Исходные байты входа изменились во время подготовки')
        сохранённое = {'схема': 'fum.сохранённый-план-наполнения.1',
                      'вход_sha256': наполнение.хэш(байты_входа), 'план': план}
        байты_плана = блоки.канонические_байты(сохранённое) + b'\n'
        _новый_план(путь_плана, корень, байты_плана)
        return {'схема': 'fum.предпросмотр-наполнения.1', 'план_sha256': наполнение.хэш(байты_плана),
                'изменяемых_файлов': len(план['файлы']), 'профиль': профиль}
    if режим != 'наполнение-применить':
        raise ValueError('Неизвестный режим наполнения')
    путь_плана, байты_плана = _прочитать(путь_плана, корень)
    if (type(ожидаемый_sha256) is not str or not блоки.ХЭШ.fullmatch(ожидаемый_sha256)
            or наполнение.хэш(байты_плана) != ожидаемый_sha256):
        raise ValueError('Сохранённый план не совпадает с одобренным SHA256')
    сохранённое = наполнение.прочитать_json(байты_плана)
    if (type(сохранённое) is not dict or set(сохранённое) != {'схема', 'вход_sha256', 'план'}
            or сохранённое['схема'] != 'fum.сохранённый-план-наполнения.1'
            or сохранённое['вход_sha256'] != наполнение.хэш(байты_входа)):
        raise ValueError('План не связан с исходными байтами входного файла')

    def проверить_байты():
        if (_прочитать(путь_входа, корень)[1] != байты_входа
                or _прочитать(путь_плана, корень)[1] != байты_плана):
            raise ValueError('Операционный вход или план изменился перед установкой')

    результат = наполнение.применить(корень, вход, сохранённое['план'], профиль=профиль,
                                    проверить_внешний_вход=проверить_байты)
    return {**результат, 'профиль': профиль}

"""Конечный перечень собственных имён формата с русской смысловой основой."""

import json
from pathlib import Path, PurePosixPath
import re


путь_перечня = Path(__file__).parent.parent / "аббревиатуры-контекста.json"
поля_записи = {"путь", "язык", "вид", "имя", "класс", "причина", "источник", "хэш_источника"}


class ОшибкаПеречня(ValueError):
    """Повреждённая политика не разрешает ни одного исключения."""


def прочитать_перечень(путь=None):
    путь = путь_перечня if путь is None else Path(путь)
    if any(часть.is_symlink() for часть in (путь, *путь.parents)):
        raise ОшибкаПеречня("путь перечня содержит символическую ссылку")
    сырые = путь.read_bytes()
    if len(сырые) > 131072:
        raise ОшибкаПеречня("перечень превышает конечную границу")

    def объект(пары):
        результат = {}
        for ключ, значение in пары:
            if ключ in результат:
                raise ОшибкаПеречня("повтор поля перечня")
            результат[ключ] = значение
        return результат

    данные = json.loads(сырые.decode("utf-8"), object_pairs_hook=объект)
    if not isinstance(данные, dict) or set(данные) != {"схема", "исключения"}:
        raise ОшибкаПеречня("неверные поля перечня")
    записи = данные["исключения"]
    if данные["схема"] != "fum.аббревиатуры-контекста.1" or not isinstance(записи, list) or not 1 <= len(записи) <= 32:
        raise ОшибкаПеречня("неверная схема или размер перечня")
    ключи = set()
    for запись in записи:
        if not isinstance(запись, dict) or set(запись) != поля_записи:
            raise ОшибкаПеречня("неверные поля исключения")
        if any(not isinstance(значение, str) or not значение for значение in запись.values()):
            raise ОшибкаПеречня("пустое либо неверное значение исключения")
        адрес = PurePosixPath(запись["путь"])
        if адрес.as_posix() != запись["путь"] or адрес.is_absolute() or ".." in адрес.parts or "\\" in запись["путь"]:
            raise ОшибкаПеречня("требуется точный относительный путь")
        if адрес.parts[:2] != ("Проекты", "рабочий-контекст"):
            raise ОшибкаПеречня("исключение вне рабочей области контекста")
        if (запись["язык"], запись["вид"], адрес.suffix) not in {
            ("python", "функция", ".py"), ("swift", "тип", ".swift"), ("swift", "функция", ".swift")
        }:
            raise ОшибкаПеречня("неверный язык или вид исключения")
        if re.fullmatch(r"[А-Яа-яЁё][А-Яа-яЁё_]*JSON", запись["имя"]) is None:
            raise ОшибкаПеречня("требуется русская основа и точная аббревиатура JSON")
        if запись["класс"] != "аббревиатура-формата-с-русской-основой":
            raise ОшибкаПеречня("неверный класс исключения")
        источник = re.fullmatch(r"git:([0-9a-f]{40}):(.+)", запись["источник"])
        if источник is None or источник[2] != запись["путь"] or re.fullmatch(r"sha256:[0-9a-f]{64}", запись["хэш_источника"]) is None:
            raise ОшибкаПеречня("требуется точный Git-источник и его хэш")
        ключ = tuple(запись[поле] for поле in ("путь", "язык", "вид", "имя"))
        if ключ in ключи:
            raise ОшибкаПеречня("повтор исключения")
        ключи.add(ключ)
    return frozenset(ключи)


def отфильтровать_аббревиатуры(объявления, путь=None):
    исключения = прочитать_перечень(путь)
    return [запись for запись in объявления
            if tuple(запись[поле] for поле in ("путь", "язык", "вид", "имя")) not in исключения]

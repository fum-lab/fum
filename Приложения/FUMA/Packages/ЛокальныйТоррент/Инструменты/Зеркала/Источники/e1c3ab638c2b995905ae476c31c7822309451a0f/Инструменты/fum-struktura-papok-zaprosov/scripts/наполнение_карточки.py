КОРЕНЬ_ИСПОЛНИТЕЛЯ = Path(__file__).resolve().parents[3]
КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
ПОЛЯ_ВХОДА = {'схема', 'задача', 'запрос', 'разрешение', 'ожидаемые_цели',
              'инструменты', 'профиль', 'поля', 'вставки'}
ПУТИ_КОНТУРА = {
    'Инструменты/fum-struktura-papok-zaprosov/scripts/' + имя
    for имя in ('request_folder_layout.py', 'struktura-papok-zaprosov.py',
                'управляемые_блоки.py', 'блоки_карточки.py', 'наполнение_карточки.py',
                'отпечатки_загрузки.py', 'наполнение_cli.py')
} | {
    'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/' + имя
    for имя in ('сверить-материалы-этапа.py', 'check-session-coherence.py', 'автор_коммита.py')
} | {'Инструменты/fum-proyektnyiye-fajlyi/scripts/project_files.py',
     'Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts/отчёты_о_запусках_проверок.py'}


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def _сверить_корни_импортов():
    собственные = [(каркас, 'request_folder_layout.py'), (рендер, 'блоки_карточки.py'),
                   (блоки, 'управляемые_блоки.py'), (загрузка, 'отпечатки_загрузки.py')]
    for модуль, имя in собственные:
        if Path(модуль.__file__) != КОРЕНЬ_ИСПОЛНИТЕЛЯ / 'Инструменты/fum-struktura-papok-zaprosov/scripts' / имя:
            raise ValueError('Каркас и модули наполнения должны принадлежать одному каноническому checkout')
    for имя, путь in [('project_files', 'Инструменты/fum-proyektnyiye-fajlyi/scripts/project_files.py'),
                       ('автор_коммита', 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/автор_коммита.py')]:
        модуль = sys.modules.get(имя)
        if модуль is not None and Path(модуль.__file__) != КОРЕНЬ_ИСПОЛНИТЕЛЯ / путь:
            raise ValueError('Импортированная зависимость находится в другом checkout')


def _модули_контура():
    _сверить_корни_импортов()
    результат = {}
    очередь = []
    for модуль in list(sys.modules.values()):
        имя = getattr(модуль, '__file__', None)
        if имя and Path(имя).resolve().is_relative_to(КОРЕНЬ_ИСПОЛНИТЕЛЯ):
            if Path(имя).resolve().relative_to(КОРЕНЬ_ИСПОЛНИТЕЛЯ).as_posix() in ПУТИ_КОНТУРА:
                очередь.append(модуль)
    посещённые = set()
    while очередь:
        модуль = очередь.pop()
        if id(модуль) in посещённые:
            continue
        посещённые.add(id(модуль))
        имя = getattr(модуль, '__file__', None)
        if not имя or not Path(имя).resolve().is_relative_to(КОРЕНЬ_ИСПОЛНИТЕЛЯ):
            continue
        путь = Path(имя)
        if not путь.is_file() or путь.is_symlink() or путь != путь.resolve():
            raise ValueError('Символический или отсутствующий путь исполняемого модуля запрещён')
        относительный = путь.relative_to(КОРЕНЬ_ИСПОЛНИТЕЛЯ).as_posix()
        прежний = результат.get(относительный)
        if (прежний is not None and getattr(прежний, 'КОД_ПРИ_ЗАГРУЗКЕ', None)
                != getattr(модуль, 'КОД_ПРИ_ЗАГРУЗКЕ', None)):
            raise ValueError('Один исходник имеет разные загруженные версии')
        результат[относительный] = модуль
        for значение in list(vars(модуль).values()):
            if isinstance(значение, types.ModuleType):
                очередь.append(значение)
            elif inspect.isfunction(значение) or inspect.isclass(значение):
                владелец = sys.modules.get(getattr(значение, '__module__', None))
                файл = getattr(владелец, '__file__', None)
                if файл and Path(файл).resolve().is_relative_to(КОРЕНЬ_ИСПОЛНИТЕЛЯ):
                    if vars(владелец).get(значение.__name__) is not значение:
                        raise ValueError('Импортированная функция или тип принадлежит прежней версии модуля')
                    очередь.append(владелец)
    return результат


def _отпечаток_модуля(модуль):
    значение = getattr(модуль, 'КОД_ПРИ_ЗАГРУЗКЕ', None)
    if type(значение) is not str or not блоки.ХЭШ.fullmatch(значение):
        raise ValueError('Исполняемая зависимость не имеет достоверного загрузочного SHA256')
    return значение


# Уже загруженные обычными импортами модули фиксируются один раз при загрузке
# наполнителя. Последующие динамические исходники компилируются из точных байтов.
ОТПЕЧАТКИ_ЗАГРУЗКИ = {
    имя: _отпечаток_модуля(модуль)
    for имя, модуль in _модули_контура().items()
}


def _сверить_код():
    for имя, модуль in _модули_контура().items():
        if имя not in ОТПЕЧАТКИ_ЗАГРУЗКИ:
            ОТПЕЧАТКИ_ЗАГРУЗКИ[имя] = _отпечаток_модуля(модуль)
    загрузка.сверить_загрузку(КОРЕНЬ_ИСПОЛНИТЕЛЯ, ОТПЕЧАТКИ_ЗАГРУЗКИ)
    return dict(ОТПЕЧАТКИ_ЗАГРУЗКИ)


@lru_cache(maxsize=2)
def _загрузить(имя):
    пути = {'охват': 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/сверить-материалы-этапа.py',
            'отчёты': 'Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts/отчёты_о_запусках_проверок.py'}
    _сверить_код()
    прежде = _модули_контура()
    путь = КОРЕНЬ_ИСПОЛНИТЕЛЯ / пути[имя]
    модуль, отпечаток = загрузка.загрузить_исходник(путь, 'наполнитель_' + имя)
    ОТПЕЧАТКИ_ЗАГРУЗКИ[пути[имя]] = отпечаток
    for новый, зависимость in _модули_контура().items():
        if новый not in прежде and новый not in ОТПЕЧАТКИ_ЗАГРУЗКИ:
            ОТПЕЧАТКИ_ЗАГРУЗКИ[новый] = _отпечаток_модуля(зависимость)
    _сверить_код()
    return модуль


def _обычный_внешний_файл(путь, корень):
    путь = Path(путь)
    if not путь.is_absolute() or путь != путь.resolve() or путь.is_relative_to(корень):
        raise ValueError('Операционный вход должен быть точным путём вне checkout')
    if any(предок.is_symlink() or os.path.lexists(предок / '.git') for предок in путь.parents):
        raise ValueError('Операционный вход находится в символическом пути или Git checkout')
    if путь.is_symlink() or not stat.S_ISREG(путь.lstat().st_mode) or путь.stat().st_size > 4 * 1024 * 1024:
        raise ValueError('Операционный вход должен быть ограниченным обычным файлом')
    return путь


def прочитать_json(байты):
    return json.loads(байты, object_pairs_hook=блоки._уникальные_поля)


def _проверить_имя(имя):
    if (type(имя) is not str or not имя or имя != PurePosixPath(имя).as_posix()
            or PurePosixPath(имя).is_absolute() or any(часть in {'.', '..', '.git'} for часть in имя.split('/'))
            or re.search(r'[\x00-\x1f\x7f\\#?]', имя) or ' -> ' in имя):
        raise ValueError('Требуется точный представимый относительный путь файла')


def _прочитать_разрешение(корень, вход):
    if type(вход) is not dict or set(вход) != ПОЛЯ_ВХОДА or вход['схема'] != 'fum.наполнение-карточки.1':
        raise ValueError('Неверная схема или поля входа наполнения')
    if type(вход['задача']) is not str or not блоки.ИДЕНТИФИКАТОР_ЗАДАЧИ.fullmatch(вход['задача']):
        raise ValueError('Нужен канонический UUID своей задачи')
    _проверить_имя(вход['запрос'])
    части = вход['запрос'].split('/')
    if (len(части) != 3 or части[0] != 'Журнал' or части[2] != 'запрос.md'
            or каркас.SESSION_PATTERN.fullmatch(части[1]) is None
            or каркас.canonical_request_path(части[1]).as_posix() != вход['запрос']):
        raise ValueError('Наполняется одна каноническая пара Журнала')
    разрешение = вход['разрешение']
    if type(разрешение) is not dict or set(разрешение) != {'путь', 'sha256'}:
        raise ValueError('Разрешение должно связывать файл и его SHA256')
    файл = _обычный_внешний_файл(разрешение['путь'], корень)
    байты = файл.read_bytes()
    if хэш(байты) != разрешение['sha256']:
        raise ValueError('Согласованный состав изменился')
    цели = прочитать_json(байты)
    if type(цели) is not list or not цели or any(type(имя) is not str for имя in цели) or len(set(цели)) != len(цели):
        raise ValueError('Разрешение должно содержать уникальные точные цели')
    for имя in цели:
        _проверить_имя(имя)
    парные = [вход['запрос'], str(PurePosixPath(вход['запрос']).with_name('отчёт.md'))]
    if not set(парные) <= set(цели):
        raise ValueError('Состав не включает собственные запрос и отчёт')
    ожидаемые = вход['ожидаемые_цели']
    if type(ожидаемые) is not list or any(type(э) is not str for э in ожидаемые) or len(set(ожидаемые)) != len(ожидаемые) or not set(ожидаемые) <= set(цели):
        raise ValueError('Ожидаемые цели должны входить в согласованный состав')
    каталог = '/'.join(части[:-1]) + '/материалы/запуски-проверок/'
    for имя in ожидаемые:
        if (not имя.startswith(каталог) or not re.fullmatch(r'[1-9][0-9]*_[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\.json', имя[len(каталог):])
                or (корень / имя).exists()):
            raise ValueError('Ожидается только конкретная ещё отсутствующая запись своей проверки')
    if type(вход['вставки']) is not list:
        raise ValueError('Журнальные вставки должны быть массивом событий')
    return sorted(цели), парные, файл, байты


def _отпечатки_шаблонов():
    return {имя: хэш((каркас.КАТАЛОГ_ШАБЛОНОВ / имя).read_bytes()) for имя in рендер.прочитать_шаблоны()}


def _снимок(корень, вход, цели, парные, разрешение):
    охват = _загрузить('охват')
    строки_git = охват.выполнить_git(корень, 'rev-parse', '--show-toplevel', 'HEAD').decode().splitlines()
    if (len(строки_git) != 2 or Path(строки_git[0]).resolve() != корень
            or re.fullmatch(r'(?:[0-9a-f]{40}|[0-9a-f]{64})', строки_git[1]) is None):
        raise ValueError('Нужен физический корень своего checkout')
    ссылка = охват.выполнить_git(корень, 'symbolic-ref', 'HEAD').decode().strip()
    коммит = строки_git[1]
    if охват.выполнить_git(корень, '--literal-pathspecs', 'ls-tree', '-z', коммит, '--', *парные):
        raise ValueError('Карточка уже существует в HEAD; закрытую историю не открываем')
    статус, строки, пути = охват.прочитать_статус(корень)
    if set(пути) - set(цели):
        raise ValueError('Git status содержит пути вне согласованного состава')
    остальные = [строка for строка in строки.splitlines()
                 if set(охват.СВЯЗНОСТЬ.parse_git_status_paths(строка)).isdisjoint(парные)]
    состояния = {}
    кэш = {}
    for имя in цели:
        путь = охват.точный_путь(корень, имя, кэш)
        состояние = охват.состояние_пути(путь)
        if состояние['тип'] == 'каталог':
            raise ValueError('Разрешение каталога вместо конечного состава запрещено')
        if состояние['тип'] == 'отсутствует' and имя not in вход['ожидаемые_цели'] and имя not in пути:
            raise ValueError('Отсутствующая цель не объявлена ожидаемой и не удаляется этапом')
        состояния[имя] = состояние
    if any(состояния[имя]['тип'] != 'файл' for имя in парные):
        raise ValueError('Собственная пара должна существовать обычными файлами')
    return {'корень': str(корень), 'ref': ссылка, 'коммит': коммит,
            'индекс_sha256': хэш(охват.выполнить_git(корень, 'ls-files', '--stage', '-z')),
            'статус_sha256': хэш(статус), 'остальной_статус_sha256': хэш('\n'.join(остальные).encode()),
            'разрешение_sha256': хэш(разрешение.read_bytes()), 'файлы': состояния,
            'исполнитель': _сверить_код(), 'шаблоны': _отпечатки_шаблонов()}


def _подготовить(корень, вход, профиль):
    начало = time.perf_counter_ns()
    вход_sha256 = хэш(блоки.канонические_байты(вход))
    корень = Path(корень).resolve()
    цели, парные, разрешение, байты_разрешения = _прочитать_разрешение(корень, вход)
    отчёты = _загрузить('отчёты')
    охват = _загрузить('охват')
    до = _снимок(корень, вход, цели, парные, разрешение)
    исходные = [(корень / имя).read_bytes() for имя in парные]
    if any(len(байты) > 4 * 1024 * 1024 for байты in исходные):
        raise ValueError('Карточка превышает ограничение конечного этапа наполнения')
    каталог = (корень / вход['запрос']).parent / 'материалы/запуски-проверок'
    записи = отчёты.прочитать_записи(каталог, вход['запрос'], разрешить_раунды=True) if каталог.exists() else []
    предметные = [(путь.relative_to(корень).as_posix(), запись, байты) for путь, запись, байты in записи]
    if any(путь not in цели for путь, _, _ in предметные):
        raise ValueError('Машинные записи проверок не включены в согласованный состав')
    после_чтения = time.perf_counter_ns()
    новые = рендер.сформировать(*исходные, вход, цели, предметные, отчёты, до['файлы'])
    состав, ошибки = охват.СВЯЗНОСТЬ.affected_files_from_request(новые[0].decode(), корень / вход['запрос'], корень)
    if ошибки or {путь.relative_to(корень).as_posix() for путь in состав} != set(цели) or состав.existing_directories or состав.deleted_subtrees or состав.deleted_direct_files_directories:
        raise ValueError('Сгенерированный блок ссылок не соответствует точному разрешению')
    после_рендера = time.perf_counter_ns()
    после = _снимок(корень, вход, цели, парные, разрешение)
    if (до != после or разрешение.read_bytes() != байты_разрешения
            or any((корень / имя).read_bytes() != байты for имя, байты in zip(парные, исходные))
            or хэш(блоки.канонические_байты(вход)) != вход_sha256):
        raise ValueError('Вход изменился во время подготовки наполнения')
    файлы = [{'путь': имя, 'текст': байты.decode(), 'режим': до['файлы'][имя]['режим']}
             for имя, прежние, байты in zip(парные, исходные, новые) if прежние != байты]
    if профиль is not None:
        профиль.update({'чтение_и_сверка_нс': после_чтения - начало,
                        'рендер_нс': после_рендера - после_чтения,
                        'повторная_сверка_нс': time.perf_counter_ns() - после_рендера,
                        'генерируемых_блоков': 7, 'файлов_для_установки': len(файлы), 'записей_проверок': len(записи)})
    return {'схема': 'fum.план-наполнения-карточки.1', 'задача': вход['задача'],
            'запрос': вход['запрос'], 'вход_sha256': вход_sha256,
            'зависимости': до, 'файлы': файлы}


def _ошибки_входа():
    ошибки = (ValueError, OSError, каркас.LayoutError, subprocess.CalledProcessError)
    отчёты = sys.modules.get('наполнитель_отчёты')
    return ошибки + (отчёты.ОшибкаОтчёта,) if отчёты is not None else ошибки


def подготовить(корень, вход, *, профиль=None):
    try:
        return _подготовить(корень, вход, профиль)
    except _ошибки_входа() as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def применить(корень, вход, план, *, профиль=None, проверить_внешний_вход=None):
    начало = time.perf_counter_ns()
    корень = Path(корень).resolve()
    if (type(план) is not dict or set(план) != {'схема', 'задача', 'запрос', 'вход_sha256', 'зависимости', 'файлы'}
            or план['схема'] != 'fum.план-наполнения-карточки.1'
            or план['вход_sha256'] != хэш(блоки.канонические_байты(вход))
            or план['задача'] != вход['задача'] or план['запрос'] != вход['запрос']):
        raise ValueError('План не связан с данным входом и задачей')
    try:
        with _загрузить('отчёты').межпроцессная_блокировка(корень, вход['запрос']):
            свежий = подготовить(корень, вход, профиль=профиль)
            цели, парные, разрешение, _ = _прочитать_разрешение(корень, вход)

            def проверить_исходники():
                if проверить_внешний_вход is not None:
                    проверить_внешний_вход()
                if (хэш(блоки.канонические_байты(вход)) != план['вход_sha256']
                        or _снимок(корень, вход, цели, парные, разрешение) != свежий['зависимости']):
                    raise ValueError('Вход изменился непосредственно перед установкой')

            if свежий != план:
                ожидаемые = json.loads(блоки.канонические_байты(план['зависимости']))
                фактические = json.loads(блоки.канонические_байты(свежий['зависимости']))
                for файл in план['файлы']:
                    if set(файл) != {'путь', 'текст', 'режим'} or файл['путь'] not in ожидаемые['файлы']:
                        raise ValueError('План содержит постороннюю установку')
                    ожидаемые['файлы'][файл['путь']] = {'тип': 'файл', 'режим': файл['режим'], 'sha256': хэш(файл['текст'].encode())}
                ожидаемые.pop('статус_sha256'); фактические.pop('статус_sha256')
                if свежий['файлы'] or ожидаемые != фактические:
                    raise ValueError('Входы плана изменились; требуется новый предпросмотр')
                проверить_исходники()
                return {'схема': 'fum.применение-наполнения.1', 'изменено': 0, 'повтор': True}
            подготовленные = [каркас.PreparedFile(PurePosixPath(файл['путь']), файл['текст'].encode(), файл['режим']) for файл in план['файлы']]

            def проверить_установку():
                if проверить_внешний_вход is not None:
                    проверить_внешний_вход()
                ожидаемые = json.loads(блоки.канонические_байты(план['зависимости']))
                for файл in план['файлы']:
                    ожидаемые['файлы'][файл['путь']] = {'тип': 'файл', 'режим': файл['режим'], 'sha256': хэш(файл['текст'].encode())}
                фактические = _снимок(корень, вход, цели, парные, разрешение)
                ожидаемые.pop('статус_sha256'); фактические.pop('статус_sha256')
                if ожидаемые != фактические or хэш(блоки.канонические_байты(вход)) != план['вход_sha256']:
                    raise ValueError('Установка не подтверждена чтением файлов и зависимостей')

            каркас._apply_prepared_transaction(корень, подготовленные,
                проверить_исходники=проверить_исходники, проверить_установку=проверить_установку)
            if профиль is not None:
                профиль['применение_нс'] = time.perf_counter_ns() - начало
            return {'схема': 'fum.применение-наполнения.1', 'изменено': len(подготовленные), 'повтор': not подготовленные}
    except _ошибки_входа() as ошибка:
        raise ValueError(str(ошибка)) from ошибка

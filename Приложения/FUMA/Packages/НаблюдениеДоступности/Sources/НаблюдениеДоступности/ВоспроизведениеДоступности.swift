import Foundation
import КонтейнерНаблюдений

public enum ВоспроизведениеДоступности {
    public static func прочитать(кореньДанных: URL, попытка: String) throws -> СостояниеДоступности {
        let сегмент = try Сегмент(кореньДанных: кореньДанных, запись: false, создать: false)
        defer { сегмент.закрыть() }
        return try прочитать(сегмент: сегмент, попытка: попытка)
    }

    // Тот же разбор используется писателем под уже удерживаемым замком.
    static func прочитать(сегмент: Сегмент, попытка: String) throws -> СостояниеДоступности {
        guard let идентификатор = UUID(uuidString: попытка),
              идентификатор.uuidString.lowercased() == попытка else {
            throw ОшибкаНаблюденияДоступности.неверныйИдентификатор
        }
        guard !сегмент.естьХвост else { throw ОшибкаКонтейнера.неполныйХвост }
        let записи = сегмент.записи
        let имяНамерения = "доступность/\(попытка)/намерение"
        let имяОтвета = "доступность/\(попытка)/ответ"
        let местоНамерения = записи.firstIndex { $0.описание.идентификатор == имяНамерения }
        let местоОтвета = записи.firstIndex { $0.описание.идентификатор == имяОтвета }
        guard let местоНамерения else {
            guard местоОтвета == nil else { throw ОшибкаНаблюденияДоступности.повреждённаяПара }
            return .отсутствует
        }
        let данныеНамерения = try сегмент.извлечь(имяНамерения)
        let намерение = try JSONDecoder().decode(НамерениеДоступности.self, from: данныеНамерения)
        try намерение.проверить()
        guard намерение.идентификаторПопытки == попытка,
              try намерение.данные() == данныеНамерения,
              try намерение.описание(ответ: false) == записи[местоНамерения].описание else {
            throw ОшибкаНаблюденияДоступности.повреждённаяПара
        }
        guard let местоОтвета else { return .неизвестно(намерение) }
        let данныеОтвета = try сегмент.извлечь(имяОтвета)
        let ответ = try JSONDecoder().decode(ОтветДоступности.self, from: данныеОтвета)
        guard ответ.версияСхемы == 1 else { throw ОшибкаНаблюденияДоступности.неподдерживаемаяСхема }
        guard местоОтвета > местоНамерения, ответ.намерение == намерение,
              try ответ.данные() == данныеОтвета,
              try намерение.описание(ответ: true) == записи[местоОтвета].описание else {
            throw ОшибкаНаблюденияДоступности.повреждённаяПара
        }
        // Чтение commit не подтверждает прежний fsync и не освежает состояние macOS.
        return .ответ(ответ, основание: .историческоеЧтение)
    }
}

import Foundation
import ApplicationServices
import КонтейнерНаблюдений

/// Один синхронный владелец сегмента; параллельные вызовы не допускаются.
public final class НаблюдательДоступности {
    private let сегмент: Сегмент
    private let вызов: () -> Bool
    public private(set) var профиль: [МеткаДоступности] = []

    public init(сегмент: Сегмент, вызов: @escaping () -> Bool = { AXIsProcessTrusted() }) {
        self.сегмент = сегмент
        self.вызов = вызов
    }

    public func наблюдать(попытка: UUID, оператор: String, версияГрафа: String) throws -> СостояниеДоступности {
        guard !оператор.isEmpty, !версияГрафа.isEmpty else { throw ОшибкаНаблюденияДоступности.неполноеПроисхождение }
        let прежнее = try ВоспроизведениеДоступности.прочитать(сегмент: сегмент, попытка: попытка.uuidString.lowercased())
        let намерение: НамерениеДоступности
        switch прежнее {
        case .неизвестно(let сохранённое): намерение = сохранённое
        case .ответ(let ответ, _): намерение = ответ.намерение
        case .отсутствует:
            намерение = НамерениеДоступности(попытка: попытка, оператор: оператор, версияГрафа: версияГрафа,
                время: ISO8601DateFormatter().string(from: Date()), процесс: ProcessInfo.processInfo.processIdentifier)
        }
        guard намерение.оператор == оператор, намерение.версияГрафа == версияГрафа else {
            throw ОшибкаНаблюденияДоступности.конфликтНамерения
        }
        return try наблюдать(намерение)
    }

    public func наблюдать(_ намерение: НамерениеДоступности) throws -> СостояниеДоступности {
        try намерение.проверить()
        let прежнее = try ВоспроизведениеДоступности.прочитать(сегмент: сегмент, попытка: намерение.идентификаторПопытки)
        switch прежнее {
        case .неизвестно(let сохранённое):
            guard сохранённое == намерение else { throw ОшибкаНаблюденияДоступности.конфликтНамерения }
            // Нельзя выяснить, был ли API вызван после прежнего commit намерения.
            return прежнее
        case .ответ(let ответ, _):
            guard ответ.намерение == намерение else { throw ОшибкаНаблюденияДоступности.конфликтНамерения }
            try подтвердитьНамерение(намерение)
            try подтвердитьОтвет(ответ)
            return .ответ(ответ, основание: .новаяФиксация)
        case .отсутствует:
            try подтвердитьНамерение(намерение)
            let (доверен, длительность) = измерить("системный-вызов") {
                let начало = DispatchTime.now().uptimeNanoseconds
                let результат = вызов()
                return (результат, DispatchTime.now().uptimeNanoseconds - начало)
            }
            let ответ = ОтветДоступности(намерение: намерение, доверен: доверен,
                длительностьНаносекунды: длительность)
            try подтвердитьОтвет(ответ)
            return .ответ(ответ, основание: .новаяФиксация)
        }
    }

    public func очиститьПрофиль() { профиль.removeAll(keepingCapacity: true) }

    private func подтвердитьНамерение(_ намерение: НамерениеДоступности) throws {
        try измерить("запись-намерения") {
            _ = try сегмент.добавить(намерение.описание(ответ: false), данные: намерение.данные())
        }
    }

    private func подтвердитьОтвет(_ ответ: ОтветДоступности) throws {
        try измерить("запись-ответа") {
            _ = try сегмент.добавить(ответ.намерение.описание(ответ: true), данные: ответ.данные())
        }
    }

    private func измерить<Значение>(_ этап: String, _ действие: () throws -> Значение) rethrows -> Значение {
        let начало = DispatchTime.now().uptimeNanoseconds
        var исход = "неуспешно"
        defer {
            // Профиль одного владельца ограничен; он не хранит наблюдаемые данные.
            if профиль.count < 4096 {
                профиль.append(МеткаДоступности(этап: этап,
                    наносекунды: DispatchTime.now().uptimeNanoseconds - начало, исход: исход, глубина: 0))
            }
        }
        let результат = try действие()
        исход = "успешно"
        return результат
    }
}

import Foundation
import Darwin
import НаблюдениеДоступности
import КонтейнерНаблюдений

@main
struct КомандаДоступности {
    static func main() {
        do { try выполнить(Array(CommandLine.arguments.dropFirst())) }
        catch {
            FileHandle.standardError.write(Data("Ошибка наблюдения: \(error)\n".utf8))
            exit(2)
        }
    }

    static func выполнить(_ аргументы: [String]) throws {
        guard let режим = аргументы.first, ["наблюдать", "прочитать", "профиль"].contains(режим) else {
            throw ОшибкаКоманды.аргументы
        }
        let допустимые: Set<String> = режим == "профиль"
            ? ["--каталог", "--повторов", "--выход", "--корень-исходников"]
            : (режим == "наблюдать" ? ["--каталог", "--попытка", "--оператор", "--версия-графа"] : ["--каталог", "--попытка"])
        let параметры = try разобрать(Array(аргументы.dropFirst()), допустимые: допустимые)
        guard let каталог = параметры["--каталог"], каталог.hasPrefix("/") else { throw ОшибкаКоманды.аргументы }
        let корень = URL(fileURLWithPath: каталог, isDirectory: true)
        if режим == "профиль" {
            guard let число = параметры["--повторов"].flatMap(Int.init), (1...100).contains(число),
                  let выход = параметры["--выход"], выход.hasPrefix("/"),
                  let исходники = параметры["--корень-исходников"], исходники.hasPrefix("/") else { throw ОшибкаКоманды.аргументы }
            try ПрофильДоступности.выполнить(корень: корень, повторы: число,
                выход: URL(fileURLWithPath: выход), исходники: URL(fileURLWithPath: исходники, isDirectory: true))
            print("Профиль четырёх стадий сохранён; повторов: \(число)")
            return
        }
        guard let строка = параметры["--попытка"], let попытка = UUID(uuidString: строка),
              попытка.uuidString.lowercased() == строка else { throw ОшибкаКоманды.аргументы }
        let состояние: СостояниеДоступности
        if режим == "прочитать" {
            состояние = try ВоспроизведениеДоступности.прочитать(кореньДанных: корень, попытка: строка)
        } else {
            guard let оператор = параметры["--оператор"], let граф = параметры["--версия-графа"] else { throw ОшибкаКоманды.аргументы }
            let сегмент = try Сегмент(кореньДанных: корень, запись: true)
            defer { сегмент.закрыть() }
            состояние = try НаблюдательДоступности(сегмент: сегмент)
                .наблюдать(попытка: попытка, оператор: оператор, версияГрафа: граф)
        }
        try вывести(состояние)
    }

    static func разобрать(_ аргументы: [String], допустимые: Set<String>) throws -> [String: String] {
        guard аргументы.count % 2 == 0 else { throw ОшибкаКоманды.аргументы }
        var параметры: [String: String] = [:]
        for место in stride(from: 0, to: аргументы.count, by: 2) {
            let ключ = аргументы[место], значение = аргументы[место + 1]
            guard допустимые.contains(ключ), параметры[ключ] == nil, !значение.isEmpty else { throw ОшибкаКоманды.аргументы }
            параметры[ключ] = значение
        }
        return параметры
    }

    static func вывести(_ состояние: СостояниеДоступности) throws {
        var ответ: [String: Any] = [:]
        switch состояние {
        case .отсутствует: ответ["состояние"] = "отсутствует"
        case .неизвестно(let намерение):
            ответ = ["состояние": "неизвестно", "попытка": намерение.идентификаторПопытки]
        case .ответ(let запись, let основание):
            ответ = ["состояние": "ответ", "попытка": запись.намерение.идентификаторПопытки,
                "доверен": запись.доверен, "основание": основание.rawValue, "длительность_наносекунды": запись.длительностьНаносекунды]
        }
        let данные = try JSONSerialization.data(withJSONObject: ответ, options: [.sortedKeys])
        FileHandle.standardOutput.write(данные + Data([10]))
    }
}

enum ОшибкаКоманды: Error { case аргументы, некорректныйПрофиль }

import XCTest
import Foundation
import КонтейнерНаблюдений
@testable import НаблюдениеДоступности

final class ТестыВоспроизведения: XCTestCase {
    func test_МетаданныеКаноническиеБайтыИПорядокОбязательны() throws {
        for вариант in 0..<5 {
            let корень = try временныйКорень()
            defer { try? FileManager.default.removeItem(at: корень) }
            let намерение = примерНамерения()
            let ответ = ОтветДоступности(намерение: намерение, доверен: true, длительностьНаносекунды: 1)
            let сегмент = try Сегмент(кореньДанных: корень, запись: true)
            let описание = try намерение.описание(ответ: false)
            let изменённое = ОписаниеНаблюдения(идентификатор: описание.идентификатор,
                тип: вариант == 0 ? "чужой-тип" : описание.тип, версияСхемы: вариант == 1 ? 2 : 1,
                источник: описание.источник, время: описание.время,
                спецификация: вариант == 2 ? Data([0]) : описание.спецификация)
            if вариант == 4 { _ = try сегмент.добавить(намерение.описание(ответ: true), данные: ответ.данные()) }
            let байты = try намерение.данные() + (вариант == 3 ? Data([32]) : Data())
            _ = try сегмент.добавить(изменённое, данные: байты)
            сегмент.закрыть()
            let файл = корень.appendingPathComponent("сегмент.fumobs"), до = try Data(contentsOf: файл)
            XCTAssertThrowsError(try ВоспроизведениеДоступности.прочитать(кореньДанных: корень, попытка: намерение.идентификаторПопытки))
            XCTAssertEqual(try Data(contentsOf: файл), до)
        }
    }

    func test_ЧтениеЗавершённойПарыНеМеняетСегмент() throws {
        let корень = try временныйКорень()
        defer { try? FileManager.default.removeItem(at: корень) }
        let намерение = примерНамерения()
        let сегмент = try Сегмент(кореньДанных: корень, запись: true)
        var вызовы = 0
        let наблюдатель = НаблюдательДоступности(сегмент: сегмент) { вызовы += 1; return false }
        _ = try наблюдатель.наблюдать(намерение)
        сегмент.закрыть()
        let файл = корень.appendingPathComponent("сегмент.fumobs")
        let до = try Data(contentsOf: файл)
        for _ in 0..<3 {
            guard case let .ответ(ответ, основание) = try ВоспроизведениеДоступности.прочитать(кореньДанных: корень, попытка: намерение.идентификаторПопытки) else { return XCTFail("Нужен исторический ответ") }
            XCTAssertFalse(ответ.доверен)
            XCTAssertEqual(основание, .историческоеЧтение)
        }
        XCTAssertEqual(вызовы, 1)
        XCTAssertEqual(try Data(contentsOf: файл), до)
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: корень.path), ["сегмент.fumobs"])
    }

    func test_НамерениеБезОтветаНеОзначаетОтрицательныйОтвет() throws {
        let корень = try временныйКорень()
        defer { try? FileManager.default.removeItem(at: корень) }
        let намерение = примерНамерения()
        let сегмент = try Сегмент(кореньДанных: корень, запись: true)
        _ = try сегмент.добавить(намерение.описание(ответ: false), данные: намерение.данные())
        let наблюдатель = НаблюдательДоступности(сегмент: сегмент) { XCTFail("Незавершённую попытку нельзя повторять скрыто"); return false }
        XCTAssertEqual(try наблюдатель.наблюдать(намерение), .неизвестно(намерение))
        сегмент.закрыть()
        XCTAssertEqual(try ВоспроизведениеДоступности.прочитать(кореньДанных: корень, попытка: намерение.идентификаторПопытки), .неизвестно(намерение))
    }

    func test_ОтсутствиеПарыИОтсутствиеФайлаРазличаются() throws {
        let корень = try временныйКорень()
        defer { try? FileManager.default.removeItem(at: корень) }
        XCTAssertThrowsError(try ВоспроизведениеДоступности.прочитать(кореньДанных: корень, попытка: UUID().uuidString.lowercased()))
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: корень.path), [])
        let сегмент = try Сегмент(кореньДанных: корень, запись: true)
        сегмент.закрыть()
        XCTAssertEqual(try ВоспроизведениеДоступности.прочитать(кореньДанных: корень, попытка: UUID().uuidString.lowercased()), .отсутствует)
    }

    func test_КонфликтВремениНеПереиспользуетОтвет() throws {
        let корень = try временныйКорень()
        defer { try? FileManager.default.removeItem(at: корень) }
        let сегмент = try Сегмент(кореньДанных: корень, запись: true)
        defer { сегмент.закрыть() }
        let попытка = UUID()
        var вызовы = 0
        let наблюдатель = НаблюдательДоступности(сегмент: сегмент) { вызовы += 1; return true }
        _ = try наблюдатель.наблюдать(примерНамерения(попытка: попытка))
        XCTAssertThrowsError(try наблюдатель.наблюдать(примерНамерения(попытка: попытка, время: "2026-10-03T14:00:00Z")))
        XCTAssertEqual(вызовы, 1)
    }

    func test_ОтветБезНамеренияИЧужаяСвязьОтклоняются() throws {
        for чужаяСвязь in [false, true] {
            let корень = try временныйКорень()
            defer { try? FileManager.default.removeItem(at: корень) }
            let намерение = примерНамерения()
            let сегмент = try Сегмент(кореньДанных: корень, запись: true)
            if чужаяСвязь { _ = try сегмент.добавить(намерение.описание(ответ: false), данные: намерение.данные()) }
            let ответ = ОтветДоступности(намерение: чужаяСвязь ? примерНамерения() : намерение, доверен: true, длительностьНаносекунды: 1)
            _ = try сегмент.добавить(намерение.описание(ответ: true), данные: ответ.данные())
            сегмент.закрыть()
            XCTAssertThrowsError(try ВоспроизведениеДоступности.прочитать(кореньДанных: корень, попытка: намерение.идентификаторПопытки))
        }
    }

    func test_ПовреждённыйИЧастичныйХвостНеРемонтируются() throws {
        for повреждение in [false, true] {
            let корень = try временныйКорень()
            defer { try? FileManager.default.removeItem(at: корень) }
            let намерение = примерНамерения()
            let сегмент = try Сегмент(кореньДанных: корень, запись: true)
            _ = try НаблюдательДоступности(сегмент: сегмент, вызов: { true }).наблюдать(намерение)
            сегмент.закрыть()
            let файл = корень.appendingPathComponent("сегмент.fumobs")
            var байты = try Data(contentsOf: файл)
            if повреждение { байты[байты.count - 1] ^= 1 } else { байты.append(0x55) }
            try байты.write(to: файл)
            XCTAssertThrowsError(try ВоспроизведениеДоступности.прочитать(кореньДанных: корень, попытка: намерение.идентификаторПопытки))
            XCTAssertEqual(try Data(contentsOf: файл), байты)
        }
    }
}

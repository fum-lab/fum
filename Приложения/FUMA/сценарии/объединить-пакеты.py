def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def канон(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()


def ключ(имя):
    return unicodedata.normalize('NFC', имя).casefold()


def требовать(условие, сообщение):
    if not условие:
        raise ValueError(сообщение)


def поля(значение, допустимые, обязательные=()):
    требовать(isinstance(значение, dict) and set(значение) <= set(допустимые) and set(обязательные) <= set(значение), 'неподдержанные или отсутствующие поля')
    return значение


def git(корень, *аргументы):
    return subprocess.check_output(['git', *аргументы], cwd=корень, stderr=subprocess.PIPE, env={имя: значение for имя, значение in os.environ.items() if not имя.startswith('GIT_')})


def путь(корень, имя):
    требовать(isinstance(имя, str) and имя and '\\' not in имя and '\x00' not in имя, 'неверный путь')
    части = PurePosixPath(имя).parts
    требовать(not имя.startswith('/') and all(часть not in ('.', '..', '.git') for часть in части) and '/'.join(части) == имя, 'небезопасный путь: ' + имя)
    текущий = корень
    for часть in части:
        требовать(часть == unicodedata.normalize('NFC', часть), 'путь должен быть NFC')
        if текущий.exists():
            совпадения = [д.name for д in текущий.iterdir() if ключ(д.name) == ключ(часть)]
            требовать(not совпадения or совпадения == [часть], 'коллизия регистра пути: ' + имя)
        текущий = текущий / часть
        требовать(not текущий.is_symlink(), 'символическая ссылка: ' + имя)
        if текущий.is_dir():
            требовать(not (текущий / '.git').exists(), 'вложенная Git-область')
    return текущий


def вызов(имя, **значения):
    return {'вызов': имя, 'аргументы': [[имя, значение] for имя, значение in значения.items()]}


def аргументы(узел, имя, допустимые, обязательные=()):
    требовать(isinstance(узел, dict) and узел.get('вызов') == имя, 'неподдержанный вызов ' + имя)
    пары = узел['аргументы']
    требовать(all(метка is not None for метка, _ in пары) and len({метка for метка, _ in пары}) == len(пары), 'повтор или позиционный аргумент')
    return поля(dict(пары), допустимые, обязательные)


class Разбор:
    def __init__(self, текст):
        требовать(len(текст.encode()) <= 262144, 'manifest слишком большой')
        шаблон = re.compile(r'\s+|//[^\n]*|/\*[^*]*(?:\*(?!/)[^*]*)*\*/|"(?:[^"\\\n]|\\["\\nrt])*"|[\w]+|[.\[\](),:=]', re.UNICODE)
        self.слова = []
        конец = 0
        for совпадение in шаблон.finditer(текст):
            требовать(совпадение.start() == конец, 'неподдержанный синтаксис manifest')
            слово = совпадение.group(); конец = совпадение.end()
            if not слово.isspace() and not слово.startswith(('//', '/*')):
                self.слова.append(слово)
        требовать(конец == len(текст), 'неподдержанный хвост manifest')
        self.номер = 0

    def взять(self, ожидаемое=None):
        требовать(self.номер < len(self.слова), 'неполный manifest')
        слово = self.слова[self.номер]; self.номер += 1
        требовать(ожидаемое is None or слово == ожидаемое, 'ожидалось ' + str(ожидаемое))
        return слово

    def сейчас(self):
        return self.слова[self.номер] if self.номер < len(self.слова) else None

    def значение(self):
        слово = self.взять()
        if слово.startswith('"'):
            return json.loads(слово)
        if слово == '[':
            значения = []
            while self.сейчас() != ']':
                значения.append(self.значение())
                if self.сейчас() != ',': break
                self.взять(',')
            self.взять(']'); return значения
        if слово == '.':
            слово += self.взять()
        требовать(re.fullmatch(r'\.?\w+', слово), 'неверное выражение')
        if self.сейчас() != '(':
            return {'символ': слово}
        self.взять('('); пары = []
        while self.сейчас() != ')':
            метка = None
            if self.номер + 1 < len(self.слова) and self.слова[self.номер + 1] == ':':
                метка = self.взять(); self.взять(':')
            пары.append([метка, self.значение()])
            if self.сейчас() != ',': break
            self.взять(',')
        self.взять(')'); return {'вызов': слово, 'аргументы': пары}


def прочитать_манифест(текст):
    требовать(re.match(r'// swift-tools-version: 6\.0\s*\n', текст), 'профиль требует swift-tools-version 6.0')
    разбор = Разбор(текст)
    for слово in ['import', 'PackageDescription', 'let', 'package', '=']:
        разбор.взять(слово)
    результат = аргументы(разбор.значение(), 'Package', ['name', 'platforms', 'products', 'dependencies', 'targets', 'swiftLanguageModes'], ['name', 'products', 'targets'])
    требовать(разбор.сейчас() is None, 'исполняемый хвост manifest запрещён')
    требовать(результат['targets'], 'пустой пакет не поддержан')
    требовать(isinstance(результат['name'], str), 'имя пакета должно быть строкой')
    for имя in ['products', 'targets', 'dependencies', 'platforms', 'swiftLanguageModes']:
        требовать(isinstance(результат.get(имя, []), list), 'ожидается массив ' + имя)
    требовать(результат.get('swiftLanguageModes', [{'символ': '.v6'}]) == [{'символ': '.v6'}], 'поддерживается только Swift 6')
    for платформа in результат.get('platforms', []):
        требовать(isinstance(платформа, dict) and платформа.get('вызов') in ['.macOS', '.iOS', '.tvOS', '.watchOS', '.visionOS'], 'неподдержанная платформа')
        пары = платформа['аргументы']
        требовать(len(пары) == 1 and пары[0][0] is None and isinstance(пары[0][1], dict) and re.fullmatch(r'\.v[0-9]+(?:_[0-9]+)?', пары[0][1].get('символ', '')), 'неподдержанная версия платформы')
    return результат


def печать(узел):
    if isinstance(узел, str): return json.dumps(узел, ensure_ascii=False)
    if isinstance(узел, list): return '[' + ', '.join(map(печать, узел)) + ']'
    if 'символ' in узел: return узел['символ']
    return узел['вызов'] + '(' + ', '.join((имя + ': ' if имя else '') + печать(значение) for имя, значение in узел['аргументы']) + ')'


def условие(значение):
    if значение is None: return
    условия = аргументы(значение, '.when', ['platforms'], ['platforms'])
    требовать(isinstance(условия['platforms'], list) and условия['platforms'] and all(э in [{'символ': '.' + п} for п in ['macOS', 'iOS', 'tvOS', 'watchOS', 'visionOS', 'linux', 'android', 'windows']] for э in условия['platforms']), 'неподдержанное условие')


def планировать(корень, вход):
    корень = корень.resolve(strict=True)
    требовать(Path(git(корень, 'rev-parse', '--show-toplevel').decode().strip()).resolve() == корень, 'нужен физический корень Git')
    поля(вход, ['схема', 'HEAD', 'назначение', 'имя', 'пакеты'], ['схема', 'HEAD', 'назначение', 'имя', 'пакеты'])
    требовать(вход['схема'] == 'fum.объединение-пакетов.1', 'неизвестная схема')
    требовать(git(корень, 'rev-parse', 'HEAD').decode().strip() == вход['HEAD'], 'HEAD изменился')
    требовать(isinstance(вход['имя'], str) and re.fullmatch(r'[\w-]+', вход['имя']), 'неверное имя пакета')
    назначение = путь(корень, вход['назначение'])
    требовать(not list(назначение.glob('Package@swift-*.swift')), 'версионный manifest назначения требует отдельного решения')
    требовать(isinstance(вход['пакеты'], list) and 2 <= len(вход['пакеты']) <= 32, 'нужно от 2 до 32 пакетов')
    индекс = git(корень, 'ls-files', '--stage', '-z')
    отслеживаемые = {}
    for строка in индекс.split(b'\0'):
        if строка:
            данные, имя = строка.split(b'\t', 1); режим, объект, стадия = данные.decode().split()
            требовать(стадия == '0', 'конфликт индекса')
            отслеживаемые[имя.decode()] = (режим, объект)
    пакеты = {}; снимки = {}; перемещения = []; цели = {}; продукты = {}; граф = {}

    def снимок(имя):
        файл = путь(корень, имя)
        требовать(имя in отслеживаемые and отслеживаемые[имя][0] in ['100644', '100755'] and файл.is_file(), 'нужен обычный отслеживаемый файл: ' + имя)
        требовать(not git(корень, 'status', '--porcelain=v1', '--', имя), 'исходник не чист: ' + имя)
        значение = {'sha256': хэш(файл.read_bytes()), 'режим': файл.stat().st_mode & 0o777, 'git': list(отслеживаемые[имя])}
        снимки[имя] = значение
        return значение

    def перенос(откуда, куда):
        данные = снимок(откуда)
        if откуда == куда: return
        требовать(not путь(корень, куда).exists(), 'назначение занято: ' + куда)
        перемещения.append({'исходник': откуда, 'назначение': куда, 'sha256': данные['sha256']})

    for запись in вход['пакеты']:
        поля(запись, ['корень', 'sha256'], ['корень', 'sha256'])
        каталог = путь(корень, запись['корень']); имя = запись['корень']
        требовать(имя not in пакеты and каталог.is_dir(), 'повтор или отсутствующий пакет')
        требовать(not list(каталог.glob('Package@swift-*.swift')), 'версионный manifest требует отдельного решения')
        манифест = имя + '/Package.swift'; данные = снимок(манифест)
        требовать(данные['sha256'] == запись['sha256'], 'manifest SHA изменился')
        пакеты[имя] = прочитать_манифест((корень / манифест).read_text())
    имена = list(пакеты)
    требовать(len({ключ(Path(и).name) for и in имена}) == len(имена), 'коллизия package identity')
    требовать(all(not (а.startswith(б + '/') or б.startswith(а + '/')) for а in имена for б in имена if а != б), 'вложенные входные пакеты')
    требовать(not (назначение / 'Package.swift').exists() or вход['назначение'] in пакеты, 'целевой manifest не включён во вход')
    платформы = пакеты[имена[0]].get('platforms', [])
    требовать(all(п.get('platforms', []) == платформы for п in пакеты.values()), 'различные платформенные минимумы требуют решения')
    for имя, пакет in пакеты.items():
        for цель in пакет['targets']:
            вид = цель.get('вызов') if isinstance(цель, dict) else None
            требовать(вид in ['.target', '.executableTarget', '.testTarget'], 'неподдержанный тип target')
            данные = аргументы(цель, вид, ['name', 'dependencies', 'path', 'resources'], ['name'])
            название = данные['name']; требовать(isinstance(название, str) and re.fullmatch(r'\w+', название), 'неверное имя target')
            требовать(ключ(название) not in цели, 'коллизия target: ' + название)
            цели[ключ(название)] = (имя, вид, данные)
        for продукт in пакет['products']:
            вид = продукт.get('вызов') if isinstance(продукт, dict) else None
            требовать(вид in ['.library', '.executable'], 'неподдержанный продукт')
            данные = аргументы(продукт, вид, ['name', 'targets', 'type'], ['name', 'targets'])
            требовать(isinstance(данные['name'], str) and re.fullmatch(r'[\w-]+', данные['name']), 'неверное имя продукта')
            требовать(ключ(данные['name']) not in продукты, 'коллизия product: ' + данные['name'])
            требовать(isinstance(данные['targets'], list) and данные['targets'] and all(isinstance(э, str) for э in данные['targets']), 'неверные product targets')
            требовать('type' not in данные or (вид == '.library' and данные['type'] in [{'символ': '.static'}, {'символ': '.dynamic'}]), 'неподдержанный тип library')
            продукты[ключ(данные['name'])] = (имя, продукт, данные)
    for имя, _, данные in продукты.values():
        требовать(all(ключ(ц) in цели and цели[ключ(ц)][0] == имя and цели[ключ(ц)][2]['name'] == ц for ц in данные['targets']), 'потерянный product target')
    итоговые_цели = []
    for название, (имя, вид, данные) in цели.items():
        каталог = данные.get('path', ('Tests/' if вид == '.testTarget' else 'Sources/') + данные['name'])
        исходный = путь(корень, имя + '/' + каталог)
        требовать(исходный.is_dir(), 'отсутствует target path')
        относительный = ('Tests/' if вид == '.testTarget' else 'Sources/') + данные['name']
        ресурсы = данные.get('resources', []); требовать(isinstance(ресурсы, list), 'неверные ресурсы')
        имена_ресурсов = set(); пути_ресурсов = set()
        for ресурс in ресурсы:
            требовать(isinstance(ресурс, dict) and ресурс.get('вызов') in ['.copy', '.process'] and len(ресурс['аргументы']) == 1 and ресурс['аргументы'][0][0] is None, 'поддерживаются только copy/process обычного файла')
            ресурсный = ресурс['аргументы'][0][1]
            файл = путь(корень, имя + '/' + каталог + '/' + ресурсный)
            требовать(файл.is_file() and файл.suffix != '.swift' and ключ(файл.name) not in имена_ресурсов, 'коллизия либо неподдержанный ресурс')
            имена_ресурсов.add(ключ(файл.name)); пути_ресурсов.add(ресурсный)
        файлы = sorted(исходный.rglob('*'))
        for файл in файлы:
            относ = файл.relative_to(исходный).as_posix()
            путь(корень, файл.relative_to(корень).as_posix())
            if файл.is_dir(): continue
            требовать(файл.suffix == '.swift' or относ in пути_ресурсов, 'файл вне поддержанного source/resource: ' + относ)
            требовать(файл.suffix.casefold() != '.md', 'Markdown-ресурс не поддержан batchtool')
            перенос(файл.relative_to(корень).as_posix(), вход['назначение'] + '/' + относительный + '/' + относ)
        требовать(any(ф.suffix == '.swift' for ф in файлы), 'пустой Swift target')
        зависимости_пакета = {}
        for зависимость in пакеты[имя].get('dependencies', []):
            запись = аргументы(зависимость, '.package', ['path'], ['path'])
            требовать(isinstance(запись['path'], str) and not Path(запись['path']).is_absolute(), 'нужен относительный package path')
            реальный = os.path.normpath(имя + '/' + запись['path'])
            путь(корень, реальный)
            идентичность = ключ(Path(реальный).name)
            требовать(идентичность not in зависимости_пакета, 'повтор identity зависимости')
            зависимости_пакета[идентичность] = реальный
            требовать(реальный in пакеты, 'все локальные зависимости должны входить в явный список пакетов')
        итоговые_зависимости = []; рёбра = []
        требовать(isinstance(данные.get('dependencies', []), list), 'неверные target dependencies')
        for зависимость in данные.get('dependencies', []):
            if isinstance(зависимость, str):
                требовать(ключ(зависимость) in цели and цели[ключ(зависимость)][0] == имя and цели[ключ(зависимость)][2]['name'] == зависимость, 'неявная внешняя зависимость не поддержана')
                итоговые_зависимости.append(зависимость); рёбра.append(зависимость); continue
            тип = зависимость.get('вызов') if isinstance(зависимость, dict) else None
            требовать(тип in ['.target', '.product'], 'неподдержанная target dependency')
            ссылка = аргументы(зависимость, тип, ['name', 'package', 'condition'] if тип == '.product' else ['name', 'condition'], ['name', 'package'] if тип == '.product' else ['name'])
            условие(ссылка.get('condition')); имя_цели = ссылка['name']
            требовать(isinstance(имя_цели, str), 'неверное имя зависимости')
            if тип == '.product':
                требовать(isinstance(ссылка['package'], str) and ключ(ссылка['package']) in зависимости_пакета, 'необъявленный package зависимости')
                другой = зависимости_пакета[ключ(ссылка['package'])]
                продукт = продукты.get(ключ(имя_цели))
                требовать(продукт and продукт[0] == другой and продукт[2]['name'] == имя_цели and продукт[1]['вызов'] == '.library' and len(продукт[2]['targets']) == 1 and 'type' not in продукт[2], 'для объединения нужен однозначный automatic library product')
                имя_цели = продукт[2]['targets'][0]
            else:
                требовать(ключ(имя_цели) in цели and цели[ключ(имя_цели)][0] == имя and цели[ключ(имя_цели)][2]['name'] == имя_цели, 'потерянная локальная цель')
            запись = {'name': имя_цели}
            if 'condition' in ссылка: запись['condition'] = ссылка['condition']
            итоговые_зависимости.append(вызов('.target', **запись)); рёбра.append(имя_цели)
        граф[данные['name']] = рёбра
        запись = {'name': данные['name']}
        if итоговые_зависимости: запись['dependencies'] = итоговые_зависимости
        запись['path'] = относительный
        if ресурсы: запись['resources'] = ресурсы
        итоговые_цели.append(вызов(вид, **запись))
    посещены = set()
    def обход(имя, стек):
        требовать(имя not in стек, 'цикл target dependencies')
        if имя in посещены: return
        for сосед in граф[имя]: обход(сосед, стек | {имя})
        посещены.add(имя)
    for имя in граф: обход(имя, set())
    for номер, имя in enumerate(пакеты):
        перенос(имя + '/Package.swift', вход['назначение'] + '/Происхождение/пакет-' + str(номер + 1) + '.swift')
    требовать(len({п['исходник'] for п in перемещения}) == len(перемещения) and len({ключ(п['назначение']) for п in перемещения}) == len(перемещения), 'повторное владение файлом или коллизия назначения')
    итог = вызов('Package', name=вход['имя'], platforms=платформы,
        products=[п[1] for п in продукты.values()],
        dependencies=[],
        targets=итоговые_цели, swiftLanguageModes=[{'символ': '.v6'}])
    манифест = '// swift-tools-version: 6.0\nimport PackageDescription\n\nlet package = ' + печать(итог) + '\n'
    for имя, данные in снимки.items():
        файл = путь(корень, имя)
        требовать(хэш(файл.read_bytes()) == данные['sha256'] and файл.stat().st_mode & 0o777 == данные['режим'], 'снимок изменился во время планирования')
    требовать(git(корень, 'ls-files', '--stage', '-z') == индекс, 'индекс изменился во время планирования')
    результат = {'схема': 'fum.план-объединения.1', 'вход': вход, 'индекс_sha256': хэш(индекс), 'переносчик_sha256': хэш(ПЕРЕНОСЧИК.read_bytes()), 'снимки': снимки,
        'пакет': {'схема': 'fum.пакет-переноса.1', 'HEAD': вход['HEAD'], 'перемещения': перемещения}, 'граф': граф,
        'целевые_каталоги': [вход['назначение'] + '/' + dict(ц['аргументы'])['path'] for ц in итоговые_цели],
        'манифест': манифест, 'манифест_sha256': хэш(манифест.encode()),
        'каталоги': sorted({str(Path(п['назначение']).parent) for п in перемещения} | {вход['назначение']})}
    return dict(результат, sha256=хэш(канон(результат)))


def проверить_план(план, ожидаемый):
    данные = dict(план); заявленный = данные.pop('sha256', None)
    требовать(заявленный == ожидаемый == хэш(канон(данные)), 'хэш просмотренного плана не совпал')
    требовать(хэш(ПЕРЕНОСЧИК.read_bytes()) == план['переносчик_sha256'], 'переносчик изменился')


def актуальный(корень, план, ожидаемый):
    проверить_план(план, ожидаемый)
    требовать(планировать(корень, план['вход']) == план, 'план устарел')


def подготовить_каталоги(корень, план, ожидаемый):
    актуальный(корень, план, ожидаемый)
    for имя in план['каталоги']:
        путь(корень, имя).mkdir(parents=True, exist_ok=True)


def переносчик():
    описание = importlib.util.spec_from_file_location('канонический_переносчик', ПЕРЕНОСЧИК)
    модуль = importlib.util.module_from_spec(описание); sys.modules[описание.name] = модуль
    описание.loader.exec_module(модуль)
    return модуль


def план_переноса(корень, план, ожидаемый):
    актуальный(корень, план, ожидаемый)
    модуль = переносчик()
    with модуль.without_inherited_git_environment():
        модуль.repository_root(корень)
        return модуль.описание_пакета(модуль.план_пакета(корень, план['пакет']))


def перенести(корень, план, ожидаемый, хэш_переноса):
    актуальный(корень, план, ожидаемый)
    модуль = переносчик()
    with модуль.without_inherited_git_environment():
        модуль.repository_root(корень)
        модуль.применить_пакет(модуль.план_пакета(корень, план['пакет']), хэш_переноса)


def завершить(корень, план, ожидаемый):
    проверить_план(план, ожидаемый)
    требовать(git(корень, 'rev-parse', 'HEAD').decode().strip() == план['вход']['HEAD'], 'HEAD изменился')
    требовать(Path(git(корень, 'rev-parse', '--show-toplevel').decode().strip()).resolve() == корень, 'нужен физический корень Git')
    итоговый_путь = план['вход']['назначение'] + '/Package.swift'
    назначения = {п['исходник']: п['назначение'] for п in план['пакет']['перемещения']}
    for старый, снимок in план['снимки'].items():
        новый = назначения.get(старый, старый); файл = путь(корень, новый)
        требовать(файл.is_file() and хэш(файл.read_bytes()) == снимок['sha256'] and файл.stat().st_mode & 0o777 == снимок['режим'], 'перенос не подтверждён: ' + новый)
        if старый != новый and путь(корень, старый).exists():
            требовать(старый == итоговый_путь and (корень / старый).read_bytes() == план['манифест'].encode(), 'прежний путь появился вновь')
        запись = git(корень, 'ls-files', '--stage', '--', новый).decode().split('\t')[0].split()
        требовать(запись == [*снимок['git'], '0'], 'индекс переноса изменён')
    ожидаемые = {назначения.get(имя, имя) for имя in план['снимки']}
    for каталог in план['целевые_каталоги']:
        фактические = set()
        for файл in путь(корень, каталог).rglob('*'):
            имя = файл.relative_to(корень).as_posix(); путь(корень, имя)
            if not файл.is_dir(): фактические.add(имя)
        требовать(фактические == {имя for имя in ожидаемые if имя.startswith(каталог + '/')}, 'инвентарь target изменился: ' + каталог)
    цель = путь(корень, итоговый_путь)
    требовать(not list(цель.parent.glob('Package@swift-*.swift')), 'добавлен версионный manifest')
    байты = план['манифест'].encode()
    требовать(хэш(байты) == план['манифест_sha256'], 'неверный manifest SHA')
    if цель.exists():
        требовать(цель.read_bytes() == байты, 'общий manifest уже существует с другими байтами')
        return
    номер, временный = tempfile.mkstemp(prefix='.манифест-', dir=цель.parent)
    try:
        with os.fdopen(номер, 'wb') as поток:
            поток.write(байты); поток.flush(); os.fsync(поток.fileno())
        os.chmod(временный, 0o644)
        os.link(временный, цель)
    finally:
        os.unlink(временный)


def уникальные(пары):
    результат = {}
    for имя, значение in пары:
        требовать(имя not in результат, 'повтор JSON поля')
        результат[имя] = значение
    return результат


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('режим', choices=['план', 'каталоги', 'план-переноса', 'перенести', 'завершить'])
    разбор.add_argument('--корень', type=Path, required=True)
    разбор.add_argument('--вход', type=Path, required=True)
    разбор.add_argument('--sha256')
    разбор.add_argument('--перенос-sha256')
    параметры = разбор.parse_args()
    try:
        требовать(параметры.вход.stat().st_size <= 4194304, 'вход превышает 4 МиБ')
        вход = json.loads(параметры.вход.read_text(), object_pairs_hook=уникальные)
        корень = параметры.корень.resolve(strict=True)
        if параметры.режим == 'план': результат = планировать(корень, вход)
        else:
            требовать(параметры.sha256 is not None, 'нужен SHA просмотренного плана')
            if параметры.режим == 'каталоги': подготовить_каталоги(корень, вход, параметры.sha256)
            elif параметры.режим == 'план-переноса':
                print(json.dumps(план_переноса(корень, вход, параметры.sha256), ensure_ascii=False, indent=2)); return 0
            elif параметры.режим == 'перенести': перенести(корень, вход, параметры.sha256, параметры.перенос_sha256)
            else: завершить(корень, вход, параметры.sha256)
            результат = {'схема': 'fum.стадия-объединения.1', 'стадия': параметры.режим, 'результат': 'успешно'}
        print(json.dumps(результат, ensure_ascii=False, indent=2)); return 0
    except (ValueError, OSError, RuntimeError, subprocess.CalledProcessError) as ошибка:
        print('отказ: ' + str(ошибка), file=sys.stderr); return 2


if __name__ == '__main__':
    raise SystemExit(главная())

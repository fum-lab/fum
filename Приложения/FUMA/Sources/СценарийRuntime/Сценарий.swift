import Foundation
import FUMStructuringOperatorMemory
import КонтейнерНаблюдений

public struct ЗамерСценария: Codable {
    public let этап: String
    public let наносекунды: UInt64
    public let исход: String
    public let глубина: Int
}

public struct РезультатСценария {
    public let выход: Data
    public let повтор: Data
    public let профиль: [ЗамерСценария]
}

public enum СценарийRuntime {
    public static func выполнить(вход: Data, корень: URL, определение: Data? = nil) throws -> РезультатСценария {
        let спецификация = try определение ?? РесурсыОпределений.прочитать("UTF-8-в-UTF-32LE")
        let оператор = try ОпределениеОператора.разобрать(спецификация)
        var профиль: [ЗамерСценария] = []
        func исполнить(_ данные: Data) throws -> Data {
            let наблюдение = try AutomationExecutor.выполнить(оператор, вход: .байты(Array(данные))) {
                профиль.append(ЗамерСценария(этап: $0.стадия, наносекунды: $0.наносекунды,
                    исход: $0.исход, глубина: 1))
            }
            guard case .байты(let байты) = наблюдение.результат else {
                throw ОшибкаКонтейнера.повреждение
            }
            return Data(байты)
        }
        let выход = try исполнить(вход)
        let писатель = try Сегмент(кореньДанных: корень, запись: true, профилировать: true)
        defer { писатель.закрыть() }
        _ = try писатель.добавить(ОписаниеНаблюдения(идентификатор: "вход", тип: "UTF-8",
            спецификация: спецификация), данные: вход)
        _ = try писатель.добавить(ОписаниеНаблюдения(идентификатор: "выход", тип: "UTF-32LE",
            спецификация: спецификация), данные: выход)
        профиль.append(contentsOf: писатель.профиль.map {
            ЗамерСценария(этап: $0.этап, наносекунды: $0.наносекунды, исход: $0.исход, глубина: $0.глубина)
        })
        писатель.закрыть()
        let читатель = try Сегмент(кореньДанных: корень, запись: false, создать: false, профилировать: true)
        defer { читатель.закрыть() }
        let повтор = try исполнить(читатель.извлечь("вход"))
        guard повтор == выход, try читатель.извлечь("выход") == выход else {
            throw ОшибкаКонтейнера.повреждение
        }
        профиль.append(contentsOf: читатель.профиль.map {
            ЗамерСценария(этап: $0.этап, наносекунды: $0.наносекунды, исход: $0.исход, глубина: $0.глубина)
        })
        return РезультатСценария(выход: выход, повтор: повтор, профиль: профиль)
    }
}

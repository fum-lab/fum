import Foundation
import КонтейнерНаблюдений

public struct РезультатИмпорта: Sendable {
    public let отчёт: ОтчётСтатистики
    public let прочитаноБайт: Int
    public let хвостБайт: Int
    public let новыхСобытий: Int
    public let байтПакета: Int
}
public actor ХранилищеСтатистики {
    private var контейнер: Сегмент?
    private let корень: URL
    private let задача: String
    private let разрешенаЗапись: Bool
    private let операции: ФайловыеОперации
    private let идентичностьКорня: ИдентичностьФайла
    private var идентичностьСегмента: ИдентичностьФайла?
    private var учёт: УчётВызовов
    private var граница: ГраницаПрефикса?
    private var пакетов = 0
    private var последний: (ПакетСтатистики, Data)?
    private var закрыто = false
    private var неопределённость = false

    public init(корень: URL, задача: String, запись: Bool, операции: ФайловыеОперации = .системные) throws {
        try проверитьЗадачу(задача)
        try проверитьВыходВнеРепозитория(корень)
        идентичностьКорня = try идентичностьФайла(корень, каталог: true)
        self.корень = корень; self.задача = задача
        разрешенаЗапись = запись; self.операции = операции
        var восстановленный = try УчётВызовов(задача: задача)
        if try существуетБезСледования(корень.appendingPathComponent("сегмент.fumobs")) || !запись {
            let открытый = try Сегмент(кореньДанных: корень, запись: запись, создать: false, операции: операции)
            do {
                guard !открытый.естьХвост else { throw ОшибкаСтатистики.повреждение }
                guard открытый.записи.count <= БюджетСтатистики.пакеты else { throw ОшибкаСтатистики.предел }
                var предыдущая: ГраницаПрефикса?
                var количество = 0
                var последняя: (ПакетСтатистики, Data)?
                for квитанция in открытый.записи {
                    guard квитанция.размер <= БюджетСтатистики.пакет else { throw ОшибкаСтатистики.предел }
                    let байты = try открытый.извлечь(квитанция.описание.идентификатор)
                    let пакет = try декодироватьПакет(байты)
                    guard try кодироватьСтатистику(квитанция.описание) == кодироватьСтатистику(описаниеПакета(пакет)) else {
                        throw ОшибкаСтатистики.повреждение
                    }
                    восстановленный = try проверитьПакет(пакет, задача: задача, до: предыдущая,
                                                          порядок: количество + 1, учёт: восстановленный)
                    количество += 1; предыдущая = пакет.после; последняя = (пакет, байты)
                }
                контейнер = открытый; граница = предыдущая; пакетов = количество; последний = последняя
                идентичностьСегмента = try идентичностьФайла(корень.appendingPathComponent("сегмент.fumobs"), каталог: false)
            } catch { открытый.закрыть(); throw error }
        }
        учёт = восстановленный
    }

    /// Ни await, ни отдельного cursor между проверкой, fsync и публикацией.
    public func импортировать(_ вход: URL) throws -> РезультатИмпорта {
        try проверитьДоступ()
        guard разрешенаЗапись else { throw ОшибкаКонтейнера.толькоЧтение }
        try проверитьМесто()
        let прочитанный = try прочитатьПрефикс(вход, задача: задача, после: граница)
        guard let новаяГраница = прочитанный.граница else {
            return РезультатИмпорта(отчёт: учёт.отчёт(граница: граница), прочитаноБайт: прочитанный.прочитаноБайт,
                хвостБайт: прочитанный.хвостБайт, новыхСобытий: 0, байтПакета: 0)
        }
        let пакет: ПакетСтатистики
        let байты: Data
        let следующий: УчётВызовов
        let новая = новаяГраница != граница
        if новая {
            guard пакетов < БюджетСтатистики.пакеты else { throw ОшибкаСтатистики.предел }
            пакет = ПакетСтатистики(версия: 1, контракт: контрактСтатистики, задача: задача,
                порядок: пакетов + 1, до: граница, после: новаяГраница, события: прочитанный.события)
            следующий = try проверитьПакет(пакет, задача: задача, до: граница, порядок: пакетов + 1, учёт: учёт)
            байты = try кодироватьСтатистику(пакет)
            guard байты.count <= БюджетСтатистики.пакет else { throw ОшибкаСтатистики.предел }
        } else {
            guard let сохранённый = последний else { throw ОшибкаСтатистики.повреждение }
            (пакет, байты) = сохранённый
            следующий = учёт
        }
        do {
            try проверитьМесто()
            if контейнер == nil {
                контейнер = try Сегмент(кореньДанных: корень, запись: true, создать: true, операции: операции)
                // Другой процесс мог завершить запись после ленивого открытия.
                guard контейнер!.записи.isEmpty, !контейнер!.естьХвост else { throw ОшибкаСтатистики.повреждение }
                идентичностьСегмента = try идентичностьФайла(корень.appendingPathComponent("сегмент.fumobs"), каталог: false)
            }
            _ = try контейнер!.добавить(описаниеПакета(пакет), данные: байты)
            try проверитьМесто()
        } catch { неопределённость = true; throw error }
        учёт = следующий
        if новая { граница = новаяГраница; пакетов += 1; последний = (пакет, байты) }
        return РезультатИмпорта(отчёт: учёт.отчёт(граница: граница), прочитаноБайт: прочитанный.прочитаноБайт,
            хвостБайт: прочитанный.хвостБайт, новыхСобытий: прочитанный.события.count, байтПакета: байты.count)
    }
    public func получить() throws -> ОтчётСтатистики {
        try проверитьДоступ()
        return учёт.отчёт(граница: граница)
    }
    public func закрыть() { контейнер?.закрыть(); закрыто = true }
    private func проверитьМесто() throws {
        try проверитьВыходВнеРепозитория(корень)
        guard try идентичностьФайла(корень, каталог: true) == идентичностьКорня else {
            throw ОшибкаСтатистики.небезопасныйПуть
        }
        if let идентичностьСегмента {
            guard try идентичностьФайла(корень.appendingPathComponent("сегмент.fumobs"), каталог: false) == идентичностьСегмента else {
                throw ОшибкаСтатистики.небезопасныйПуть
            }
        }
    }
    private func проверитьДоступ() throws {
        guard !закрыто else { throw ОшибкаСтатистики.закрыто }
        guard !неопределённость else { throw ОшибкаСтатистики.неопределённаяЗапись }
    }
}

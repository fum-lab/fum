import Foundation
import Darwin
import CryptoKit

public func прочитатьПрефикс(_ вход: URL, задача: String,
                            после: ГраницаПрефикса? = nil) throws -> ПрочитанныйПрефикс {
    try проверитьЗадачу(задача)
    guard вход.isFileURL, вход.path.hasPrefix("/"), !вход.path.utf8.contains(0),
          !вход.absoluteString.lowercased().contains("%00") else { throw ОшибкаСтатистики.небезопасныйПуть }
    let дескриптор = open(вход.path, O_RDONLY | O_CLOEXEC | O_NOFOLLOW | O_NONBLOCK)
    guard дескриптор >= 0 else { throw ОшибкаСтатистики.система(errno) }
    defer { _ = close(дескриптор) }
    var начальный = stat()
    guard fstat(дескриптор, &начальный) == 0 else { throw ОшибкаСтатистики.система(errno) }
    guard начальный.st_mode & S_IFMT == S_IFREG else { throw ОшибкаСтатистики.небезопасныйПуть }
    guard начальный.st_size >= 0, начальный.st_size <= БюджетСтатистики.вход else { throw ОшибкаСтатистики.предел }
    let размер = Int(начальный.st_size)
    if let после {
        guard после.байт > 0, после.байт <= размер, после.строк > 0,
              после.строк <= БюджетСтатистики.строки else { throw ОшибкаСтатистики.изменённыйПрефикс }
    }
    var буфер = [UInt8](repeating: 0, count: БюджетСтатистики.блок)
    var незавершённая = Data()
    var прочитано = 0
    var конец = 0
    var строк = 0
    var хэш = SHA256()
    var прежнийПодтверждён = после == nil
    var события: [СобытиеВызова] = []
    while прочитано < размер {
        let число = буфер.withUnsafeMutableBytes { область in
            Darwin.read(дескриптор, область.baseAddress!, min(область.count, размер - прочитано))
        }
        if число < 0, errno == EINTR { continue }
        guard число > 0 else { throw ОшибкаСтатистики.изменённыйПрефикс }
        прочитано += число
        var началоЧасти = 0
        for позиция in 0..<число where буфер[позиция] == 10 {
            guard незавершённая.count + позиция + 1 - началоЧасти <= БюджетСтатистики.строка else {
                throw ОшибкаСтатистики.предел
            }
            незавершённая.append(contentsOf: буфер[началоЧасти...позиция])
            началоЧасти = позиция + 1
            let началоСтроки = конец
            конец += незавершённая.count
            строк += 1
            guard строк <= БюджетСтатистики.строки else { throw ОшибкаСтатистики.предел }
            хэш.update(data: незавершённая)
            if let после, конец == после.байт {
                guard строк == после.строк, текстХэша(хэш.finalize()) == после.sha256 else {
                    throw ОшибкаСтатистики.изменённыйПрефикс
                }
                прежнийПодтверждён = true
            }
            if let после, конец > после.байт, !прежнийПодтверждён {
                throw ОшибкаСтатистики.изменённыйПрефикс
            }
            if строк == 1 || конец > (после?.байт ?? 0) {
                // Foundation не удерживает временные объекты всех строк до конца прохода.
                try autoreleasepool {
                    let объект = try объектСтроки(незавершённая)
                    if строк == 1 || объект["type"] as? String == "session_meta" {
                        guard объект["type"] as? String == "session_meta",
                              let данные = объект["payload"] as? [String: Any],
                              let идентификатор = данные["id"] as? String,
                              Array(идентификатор.utf8) == Array(задача.utf8) else {
                            throw ОшибкаСтатистики.идентичность
                        }
                    }
                    if конец > (после?.байт ?? 0),
                       let событие = try событиеСтроки(объект, происхождение: ПроисхождениеСтроки(
                        строка: строк, начало: началоСтроки, конец: конец,
                        sha256: хэшБайтов(незавершённая), контракт: контрактСтатистики)) {
                        guard события.count < БюджетСтатистики.события else { throw ОшибкаСтатистики.предел }
                        события.append(событие)
                    }
                }
            }
            незавершённая.removeAll(keepingCapacity: true)
        }
        if началоЧасти < число {
            guard незавершённая.count + число - началоЧасти <= БюджетСтатистики.строка else {
                throw ОшибкаСтатистики.предел
            }
            незавершённая.append(contentsOf: буфер[началоЧасти..<число])
        }
    }
    guard прежнийПодтверждён else { throw ОшибкаСтатистики.изменённыйПрефикс }
    var конечный = stat()
    var поПути = stat()
    guard fstat(дескриптор, &конечный) == 0, lstat(вход.path, &поПути) == 0,
          конечный.st_dev == начальный.st_dev, конечный.st_ino == начальный.st_ino,
          поПути.st_dev == начальный.st_dev, поПути.st_ino == начальный.st_ino,
          конечный.st_size == начальный.st_size,
          конечный.st_mtimespec.tv_sec == начальный.st_mtimespec.tv_sec,
          конечный.st_mtimespec.tv_nsec == начальный.st_mtimespec.tv_nsec,
          конечный.st_ctimespec.tv_sec == начальный.st_ctimespec.tv_sec,
          конечный.st_ctimespec.tv_nsec == начальный.st_ctimespec.tv_nsec else {
        throw ОшибкаСтатистики.изменённыйПрефикс
    }
    let граница = строк == 0 ? nil : ГраницаПрефикса(байт: конец, строк: строк, sha256: текстХэша(хэш.finalize()))
    return ПрочитанныйПрефикс(граница: граница, события: события,
        хвостБайт: незавершённая.count, прочитаноБайт: прочитано)
}

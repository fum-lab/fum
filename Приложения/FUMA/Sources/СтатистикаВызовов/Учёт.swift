import Foundation

public struct УчётВызовов: Sendable {
    let задача: String
    private var события: [СобытиеВызова] = []
    private var вызовы: [String: СобытиеВызова] = [:]
    private var результаты: [String: СобытиеВызова] = [:]
    private var дубликатов = 0
    public init(задача: String) throws {
        try проверитьЗадачу(задача)
        self.задача = задача
    }
    public mutating func принять(_ новые: [СобытиеВызова]) throws {
        guard новые.count <= БюджетСтатистики.события - события.count else { throw ОшибкаСтатистики.предел }
        var следующий = self
        for событие in новые {
            try проверитьСобытие(событие)
            if let ключ = событие.идентификатор {
                let прежнее = событие.направление == .вызов ? следующий.вызовы[ключ] : следующий.результаты[ключ]
                if let прежнее {
                    guard прежнее.происхождение.sha256 == событие.происхождение.sha256,
                          прежнее.семейство == событие.семейство,
                          прежнее.инструмент == событие.инструмент,
                          прежнее.момент == событие.момент else {
                        throw ОшибкаСтатистики.конфликтВызова
                    }
                    следующий.дубликатов += 1
                } else if событие.направление == .вызов { следующий.вызовы[ключ] = событие }
                else { следующий.результаты[ключ] = событие }
            }
            следующий.события.append(событие)
        }
        self = следующий
    }
    public func отчёт(граница: ГраницаПрефикса? = nil) -> ОтчётСтатистики {
        let состояния = вызовы.keys.sorted().map { ключ -> СостояниеВызова in
            let вызов = вызовы[ключ]!
            let результат = результаты[ключ]
            let связь: СвязьРезультата = результат == nil ? .отсутствует :
                (вызов.семейство == результат!.семейство ? .сопряжён : .несовместимоеСемейство)
            var задержка: Int64?
            if связь == .сопряжён, let начало = вызов.момент.наносекундыОтЭпохи,
               let конец = результат?.момент.наносекундыОтЭпохи, конец >= начало {
                let разность = конец.subtractingReportingOverflow(начало)
                if !разность.overflow { задержка = разность.partialValue }
            }
            return СостояниеВызова(вызов: вызов, результат: результат, связь: связь, задержкаНаносекунды: задержка)
        }
        let неизвестныеВызовы = события.filter { $0.направление == .вызов && $0.идентификатор == nil }
        let несопряжённые = результаты.values.filter {
            guard let ключ = $0.идентификатор, let вызов = вызовы[ключ] else { return true }
            return вызов.семейство != $0.семейство
        } + события.filter { $0.направление == .результат && $0.идентификатор == nil }
        let безПары = несопряжённые.sorted { $0.происхождение.строка < $1.происхождение.строка }
        let группы = Dictionary(grouping: состояния, by: { $0.вызов.инструмент })
        let неизвестныеГруппы = Dictionary(grouping: неизвестныеВызовы, by: \.инструмент)
        let имена = Set(группы.keys).union(неизвестныеГруппы.keys)
            .sorted { ($0 ?? "") < ($1 ?? "") }
        let инструменты = имена.map { имя in
            let группа = группы[имя] ?? []
            let пары = группа.filter { $0.связь == .сопряжён }
            return ИтогИнструмента(инструмент: имя, прямыхВызовов: группа.count,
                вызововБезИдентичности: неизвестныеГруппы[имя]?.count ?? 0,
                сопряжённыхРезультатов: пары.count, безРезультата: группа.filter { $0.связь == .отсутствует }.count,
                неоднозначныхСвязей: группа.filter { $0.связь == .несовместимоеСемейство }.count,
                неизвестныхЗадержек: пары.filter { $0.задержкаНаносекунды == nil }.count,
                задержкиНаносекунды: пары.compactMap(\.задержкаНаносекунды).sorted())
        }
        return ОтчётСтатистики(контракт: контрактСтатистики, задача: задача, граница: граница,
            прямыхВызовов: состояния.count, сопряжённыхРезультатов: состояния.filter { $0.связь == .сопряжён }.count,
            несопряжённыхРезультатов: безПары.count, дубликатов: дубликатов, наблюдения: события,
            вызовы: состояния, вызовыБезИдентичности: неизвестныеВызовы,
            результатыБезПары: безПары, инструменты: инструменты)
    }
}

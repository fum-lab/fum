import КонтейнерНаблюдений
import Foundation
import Darwin

do {
    let аргументы = Array(CommandLine.arguments.dropFirst())
    guard аргументы.count >= 2, аргументы[1].hasPrefix("/") else {
        throw ОшибкаКонтейнера.небезопасныйПуть
    }
    let корень = URL(fileURLWithPath: аргументы[1], isDirectory: true)
    if аргументы[0] == "добавить", аргументы.count == 5 || аргументы.count == 6 {
        let данные = try прочитатьВход(аргументы[4])
        let спецификация = аргументы.count == 6 ? try прочитатьВход(аргументы[5], предел: 65_536) : Data("неинтерпретируемые байты".utf8)
        guard спецификация.count <= 65_536 else { throw ОшибкаКонтейнера.предел }
        let писатель = try Сегмент(кореньДанных: корень, запись: true)
        defer { писатель.закрыть() }
        let описание = ОписаниеНаблюдения(идентификатор: аргументы[2], тип: аргументы[3], спецификация: спецификация)
        try вывестиJSON(писатель.добавить(описание, данные: данные))
    } else if аргументы[0] == "удерживать", аргументы.count == 2 {
        let писатель = try Сегмент(кореньДанных: корень, запись: true)
        defer { писатель.закрыть() }
        try вывестиJSON(["состояние": "замок-удерживается"])
        // Явный барьер для диагностики конкуренции; EOF или байт отпускает замок.
        _ = try FileHandle.standardInput.read(upToCount: 1)
    } else {
        throw ОшибкаКонтейнера.повреждение
    }
} catch {
    try? FileHandle.standardError.write(contentsOf: Data("Писатель: \(error)\n".utf8))
    exit(1)
}

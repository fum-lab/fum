import Foundation

public func читаемыйТекст(_ снимок: Снимок) throws -> String {
    func какJSON<Значение: Encodable>(_ значение: Значение) throws -> String {
        String(decoding: try каноническийJSON(значение), as: UTF8.self)
    }
    var строки = [
        "Синтетический снимок v\(снимок.версия)",
        "Задача: " + (try какJSON(снимок.задача)),
        "Момент: логический такт \(снимок.такт); не атомарный снимок реального runtime.",
        "Поля без свидетельств: " + (try какJSON(снимок.неизвестныеПоля)),
        "Модель конкретного хода не переносится на другие ходы."
    ]
    for поле in снимок.поля {
        строки.append("\(поле.поле.rawValue) [\(try какJSON(поле.контекст))]: \(поле.знание.rawValue)")
        for кандидат in поле.кандидаты {
            строки.append("  \(try какJSON(кандидат.значение)); \(кандидат.устарело ? "устарело" : "в сроке"); свидетельство \(try какJSON(кандидат.свидетельство))")
        }
    }
    строки.append("Не перечислена в области ответа (не доказательство отсутствия): " + (try какJSON(снимок.разрывыОхвата)))
    строки.append("Недоступные каналы (отказ действует для всех экземпляров): " + (try какJSON(снимок.недоступныеКаналы)))
    строки.append("Проигнорированные свидетельства: " + (try какJSON(снимок.проигнорированы)))
    for операция in снимок.операции {
        строки.append("Операция \(try какJSON(операция.идентификатор)): \(операция.фаза.rawValue); эффект " +
            (операция.подтверждение == nil ? "НЕ ПОДТВЕРЖДЁН" : "подтверждён свидетельством \(try какJSON(операция.подтверждение))"))
        строки.append("  " + (try какJSON(операция)))
    }
    строки.append("Последняя подтверждённая корректировка: " + (try какJSON(снимок.последняяПодтверждённаяКорректировка)))
    строки.append("Исходные свидетельства; ID, источник, такт/срок, охват, область и исходный факт:")
    for наблюдение in снимок.наблюдения { строки.append(try какJSON(наблюдение)) }
    return строки.joined(separator: "\n") + "\n"
}

public func читаемыйMarkdown(_ снимок: Снимок) throws -> String {
    // Кодовый блок с отступом не исполняет Markdown/HTML из свидетельств.
    "# Синтетический снимок агентской задачи\n\n" +
        (try читаемыйТекст(снимок)).split(separator: "\n", omittingEmptySubsequences: false)
            .map { "    " + $0 }.joined(separator: "\n") + "\n"
}

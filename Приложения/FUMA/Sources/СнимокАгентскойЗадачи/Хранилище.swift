import Foundation
import CryptoKit
import КонтейнерНаблюдений

struct Переход: Codable, Equatable, Sendable {
    let порядок: Int
    let до: String
    let после: String
}
struct СохранённоеНаблюдение: Codable, Equatable, Sendable {
    let версия: Int
    let наблюдение: Наблюдение
    let переход: Переход
}
func хэшСнимка(_ снимок: Снимок) throws -> String {
    SHA256.hash(data: try каноническийJSON(снимок)).map { String(format: "%02x", $0) }.joined()
}
func описаниеЗаписи(_ наблюдение: Наблюдение) throws -> ОписаниеНаблюдения {
    ОписаниеНаблюдения(идентификатор: наблюдение.идентификатор,
        тип: "синтетический-снимок-задачи/наблюдение-и-переход", версияСхемы: 1,
        источник: String(decoding: try каноническийJSON(наблюдение.источник), as: UTF8.self),
        время: "логический-такт:" + String(наблюдение.такт),
        спецификация: Data("FUM-STEP-0159: редуктор v1; канонический JSON; SHA-256 снимков; только синтетика".utf8))
}
func следующийПереход(_ наблюдение: Наблюдение, _ редуктор: Редуктор, хэшДо: String? = nil) throws
    -> (Редуктор, СохранённоеНаблюдение) {
    var следующий = редуктор
    try следующий.принять(наблюдение)
    let запись = СохранённоеНаблюдение(версия: 1, наблюдение: наблюдение,
        переход: Переход(порядок: следующий.снимок.наблюдения.count,
                         до: try хэшДо ?? хэшСнимка(редуктор.снимок), после: try хэшСнимка(следующий.снимок)))
    return (следующий, запись)
}

/// Единственный владелец синхронного non-Sendable контейнера.
/// Между редукцией, записью и публикацией снимка нет точек приостановки.
public actor ХранилищеСнимка {
    private let контейнер: Сегмент
    private let разрешенаЗапись: Bool
    private var редуктор: Редуктор
    private var сохранённые: [String: СохранённоеНаблюдение]
    private var проверенныйХэш: String
    private var закрыто = false
    private var неопределённаяЗапись = false

    public init(корень: URL, задача: Задача, запись: Bool,
                операции: ФайловыеОперации = .системные) throws {
        try проверитьЗадачу(задача)
        let открытый = try Сегмент(кореньДанных: корень, запись: запись, создать: запись, операции: операции)
        do {
            guard !открытый.естьХвост else { throw ОшибкаСнимка.неполныйКонтейнер }
            guard открытый.записи.count <= БюджетСнимка.наблюдения else { throw ОшибкаСнимка.предел }
            var восстановленный = try Редуктор(задача: задача)
            var предыдущийХэш = try хэшСнимка(восстановленный.снимок)
            var записи: [String: СохранённоеНаблюдение] = [:]
            for квитанция in открытый.записи {
                guard квитанция.размер <= БюджетСнимка.запись else { throw ОшибкаСнимка.предел }
                let данные = try открытый.извлечь(квитанция.описание.идентификатор)
                let запись = try декодировать(СохранённоеНаблюдение.self, данные, предел: БюджетСнимка.запись)
                guard запись.версия == 1 else { throw ОшибкаСнимка.версия }
                let наблюдение = запись.наблюдение
                guard записи[наблюдение.идентификатор] == nil,
                      try каноническийJSON(квитанция.описание) == каноническийJSON(описаниеЗаписи(наблюдение)) else {
                    throw ОшибкаСнимка.неверныйПереход
                }
                let (следующий, ожидаемая) = try следующийПереход(наблюдение, восстановленный, хэшДо: предыдущийХэш)
                guard try каноническийJSON(запись) == каноническийJSON(ожидаемая) else {
                    throw ОшибкаСнимка.неверныйПереход
                }
                восстановленный = следующий
                предыдущийХэш = ожидаемая.переход.после
                записи[наблюдение.идентификатор] = запись
            }
            контейнер = открытый
            разрешенаЗапись = запись
            редуктор = восстановленный
            сохранённые = записи
            проверенныйХэш = предыдущийХэш
        } catch {
            открытый.закрыть()
            throw error
        }
    }

    public func принять(_ наблюдение: Наблюдение) throws -> Снимок {
        try проверитьДоступность()
        guard разрешенаЗапись else { throw ОшибкаКонтейнера.толькоЧтение }
        try проверитьНаблюдение(наблюдение)
        guard наблюдение.задача == редуктор.снимок.задача else { throw ОшибкаСнимка.чужаяЗадача }
        let следующий: Редуктор
        let запись: СохранённоеНаблюдение
        if let прежняя = сохранённые[наблюдение.идентификатор] {
            guard try каноническийJSON(прежняя.наблюдение) == каноническийJSON(наблюдение) else {
                throw ОшибкаСнимка.конфликтИдентификатора
            }
            // После неоднозначного fsync исходный переход уже может быть на диске.
            // Повторяем именно его байты и успешную синхронизацию, не редукцию.
            следующий = редуктор
            запись = прежняя
        } else {
            (следующий, запись) = try следующийПереход(наблюдение, редуктор, хэшДо: проверенныйХэш)
        }
        let данные = try каноническийJSON(запись)
        guard данные.count <= БюджетСнимка.запись else { throw ОшибкаСнимка.предел }
        do {
            _ = try контейнер.добавить(описаниеЗаписи(наблюдение), данные: данные)
        } catch {
            // Точная граница: состояние на диске неизвестно до закрытия/replay.
            неопределённаяЗапись = true
            throw error
        }
        редуктор = следующий
        // Повтор старого события не откатывает хэш текущего снимка к старому переходу.
        if сохранённые[наблюдение.идентификатор] == nil { проверенныйХэш = запись.переход.после }
        сохранённые[наблюдение.идентификатор] = запись
        return редуктор.снимок
    }

    public func проиграть(_ сценарий: Сценарий) throws -> Снимок {
        try проверитьДоступность()
        try проверитьСценарий(сценарий)
        guard сценарий.задача == редуктор.снимок.задача else { throw ОшибкаСнимка.чужаяЗадача }
        var предварительный = редуктор
        for наблюдение in сценарий.наблюдения { try предварительный.принять(наблюдение) }
        for наблюдение in сценарий.наблюдения { _ = try принять(наблюдение) }
        return редуктор.снимок
    }
    public func получить() throws -> Снимок {
        try проверитьДоступность()
        return редуктор.снимок
    }
    public func закрыть() {
        контейнер.закрыть()
        закрыто = true
    }
    private func проверитьДоступность() throws {
        guard !закрыто else { throw ОшибкаСнимка.закрыт }
        guard !неопределённаяЗапись else { throw ОшибкаСнимка.неполныйКонтейнер }
    }
}

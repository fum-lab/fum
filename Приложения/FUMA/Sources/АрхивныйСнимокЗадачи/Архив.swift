import Foundation
import СнимокАгентскойЗадачи
import КонтейнерНаблюдений

public actor АрхивЗадачи {
    private let контейнер: Сегмент
    private let uuid: String
    private let запись: Bool
    private let бюджет: БюджетАрхива
    private var результат: РезультатАрхива?
    private var измерения = ПрофильАрхива()
    private var закрыт = false
    private var неопределённаяЗапись = false

    public init(корень: URL, ожидаемыйUUID: String, запись: Bool,
                бюджет: БюджетАрхива = .init(), операции: ФайловыеОперации = .системные,
                восстановитьХвост: Bool = false) throws {
        try проверитьUUID(ожидаемыйUUID)
        let максимум = БюджетАрхива()
        guard бюджет.байты > 0, бюджет.байты <= максимум.байты,
              бюджет.строка > 0, бюджет.строка <= максимум.строка,
              бюджет.строки > 0, бюджет.строки <= максимум.строки,
              бюджет.глубина > 0, бюджет.глубина <= максимум.глубина,
              бюджет.узлыСтроки > 0, бюджет.узлыСтроки <= максимум.узлыСтроки,
              бюджет.записи > 0, бюджет.записи <= максимум.записи,
              !восстановитьХвост || запись else { throw ОшибкаАрхива.предел }
        let начало = DispatchTime.now().uptimeNanoseconds
        let открытый = try Сегмент(кореньДанных: корень, запись: запись, создать: запись, операции: операции, профилировать: true)
        do {
            if открытый.естьХвост {
                guard восстановитьХвост else { throw ОшибкаАрхива.неполныйКонтейнер }
            }
            guard открытый.записи.count <= бюджет.записи else { throw ОшибкаАрхива.предел }
            var последний: РезультатАрхива?
            for квитанция in открытый.записи {
                guard квитанция.размер <= 65_536 else { throw ОшибкаАрхива.предел }
                let данные = try открытый.извлечь(квитанция.описание.идентификатор)
                let следующий = try восстановитьРезультат(данные, uuid: ожидаемыйUUID, прежний: последний?.архив, бюджет: бюджет)
                guard квитанция.описание == описаниеАрхива(следующий.архив) else { throw ОшибкаАрхива.повреждениеАрхива }
                последний = следующий
            }
            // Никакой обрезки до проверки идентичности и семантики всех committed объектов.
            if открытый.естьХвост { try открытый.восстановитьХвост() }
            контейнер = открытый; uuid = ожидаемыйUUID; self.запись = запись; self.бюджет = бюджет
            результат = последний
            измерения.replay = DispatchTime.now().uptimeNanoseconds - начало
        } catch { открытый.закрыть(); throw error }
    }
    public func импортировать(_ источник: URL, полныйРазбор: Bool = false) throws -> РезультатАрхива {
        try проверитьДоступ()
        guard запись else { throw ОшибкаКонтейнера.толькоЧтение }
        let начало = DispatchTime.now().uptimeNanoseconds
        var профиль = ПрофильАрхива(); профиль.replay = измерения.replay
        let прежний = результат?.архив
        var выбор = ВыборФактов()
        if let прежний, !полныйРазбор {
            выбор = ВыборФактов(sessionMeta: прежний.sessionMeta, каталогRuntime: прежний.каталогRuntime,
                               последнийХод: прежний.последнийХод, модельХода: прежний.модельХода)
        }
        let (граница, пик) = try прочитатьПрефикс(источник, бюджет: бюджет, прежняя: прежний?.граница) { данные, позиция in
            if !полныйРазбор, let прежний, позиция.конец <= прежний.граница.байты { return }
            let началоРазбора = DispatchTime.now().uptimeNanoseconds
            try выбор.принять(данные, позиция: позиция, uuid: uuid, бюджет: бюджет)
            профиль.разбор += DispatchTime.now().uptimeNanoseconds - началоРазбора
            профиль.разобраноСтрок += 1
        }
        профиль.чтениеИХэширование = DispatchTime.now().uptimeNanoseconds - начало - профиль.разбор
        профиль.пикБуфераСтроки = пик
        let началоРедукции = DispatchTime.now().uptimeNanoseconds
        let точныйПовтор = прежний?.граница == граница
        let предыдущий = точныйПовтор ? прежний?.предыдущийSHA : try прежний.map { хэшАрхива(try каноническийJSON($0)) }
        let следующий = try собратьРезультат(uuid, выбор, граница, предыдущий)
        if точныйПовтор, следующий != результат { throw ОшибкаАрхива.повреждениеАрхива }
        if !точныйПовтор, контейнер.записи.count >= бюджет.записи { throw ОшибкаАрхива.предел }
        let данные = try каноническийJSON(следующий.архив)
        guard данные.count <= 65_536 else { throw ОшибкаАрхива.предел }
        профиль.редукция = DispatchTime.now().uptimeNanoseconds - началоРедукции
        контейнер.очиститьПрофиль()
        let началоЗаписи = DispatchTime.now().uptimeNanoseconds
        do { _ = try контейнер.добавить(описаниеАрхива(следующий.архив), данные: данные) }
        catch { неопределённаяЗапись = true; throw error }
        let всёПодтверждение = DispatchTime.now().uptimeNanoseconds - началоЗаписи
        профиль.fsync = контейнер.профиль.filter { $0.этап.hasPrefix("синхронизация-") }.reduce(0) { $0 + $1.наносекунды }
        профиль.запись = всёПодтверждение - профиль.fsync
        if точныйПовтор { профиль.повтор = DispatchTime.now().uptimeNanoseconds - начало }
        // Единственная точка публикации результата и курсора — после двух успешных fsync.
        результат = следующий; измерения = профиль
        return следующий
    }
    public func получить() throws -> РезультатАрхива? { try проверитьДоступ(); return результат }
    public func числоЗаписей() -> Int { контейнер.записи.count }
    public func профиль() -> ПрофильАрхива { измерения }
    public func закрыть() { контейнер.закрыть(); закрыт = true }
    private func проверитьДоступ() throws {
        guard !закрыт else { throw ОшибкаАрхива.закрыт }
        guard !неопределённаяЗапись else { throw ОшибкаАрхива.неопределённаяЗапись }
    }
}

public struct МеткаИсполнения: Encodable {
    public let стадия: String
    public let наносекунды: UInt64
    public let исход: String
    public let глубина: Int
}

public enum ОшибкаКомандногоИсполнения: String, Error {
    case аргументы, приватныйКаталог, кодировка, записьПовтора, расхождениеПовтора
}

private struct ПрофильИсполнителя: Codable, Equatable {
    let схема: String
    let байтовВхода: Int
    let байтовРезультата: Int
    let операций: Int
    let записейТрассы: Int

    static let текущий = ПрофильИсполнителя(схема: "fuma.профиль-исполнителя.1",
        байтовВхода: 262_144, байтовРезультата: 1_048_576, операций: 16_777_216, записейТрассы: 256)

    var пределы: ПределыИсполнения {
        ПределыИсполнения(байтовВхода: байтовВхода, байтовРезультата: байтовРезультата,
            операций: операций, записейТрассы: записейТрассы)
    }
}

private enum ВидВхода: String, Codable { case текст, байты }

private struct ПринятыеДанные: Codable {
    let исходноеОпределение: Data
    let определение: Data
    let вход: Data
    let типВхода: ВидВхода
    let профиль: ПрофильИсполнителя
}

private struct ЗаписьИсполнения: Encodable {
    let схема = "fuma.исполнение-оператора.1"
    let принятыеДанные: ПринятыеДанные
    let наблюдение: НаблюдениеОператора
}

private struct ВходПовтора: Decodable {
    struct ИдентичностьНаблюдения: Decodable { let хэшНаблюдения: String }
    let схема: String
    let принятыеДанные: ПринятыеДанные
    let наблюдение: ИдентичностьНаблюдения
}

private struct ОтветИсполнения: Encodable {
    let схема = "fuma.результат-исполнения.1"
    let квитанция: Квитанция
    let наблюдение: НаблюдениеОператора
}

public enum КомандноеИсполнениеОператора {
    private static let параметры: Set<String> = ["--определение", "--вход", "--тип-входа", "--журнал"]

    public static func выбран(аргументы: [String]) -> Bool {
        аргументы.contains { параметры.contains($0) || $0 == "--выполнить-оператор" || $0 == "--повторить-оператор" }
    }

    /// Синхронный вызов: исполнитель и контейнер работают в процессе основного приложения.
    public static func выполнить(
        аргументы: [String], операции: ФайловыеОперации = .системные,
        профиль: ((МеткаИсполнения) -> Void)? = nil
    ) throws -> Data {
        func измерить<Значение>(_ стадия: String, _ действие: () throws -> Значение) rethrows -> Значение {
            let начало = DispatchTime.now().uptimeNanoseconds
            var исход = "отказ"
            defer { профиль?(МеткаИсполнения(стадия: стадия,
                наносекунды: DispatchTime.now().uptimeNanoseconds - начало, исход: исход, глубина: 0)) }
            let значение = try действие()
            исход = "успешно"
            return значение
        }

        let подготовка = try измерить("вход") {
            try принять(аргументы)
        }
        let принято = подготовка.данные
        let определение = try измерить("декодирование") {
            guard принято.профиль == .текущий else { throw ОшибкаКомандногоИсполнения.записьПовтора }
            let определение = try ОпределениеОператора.разобрать(принято.исходноеОпределение)
            let канонические = try определение.данные()
            if let сохранённое = подготовка.каноническое, сохранённое != канонические {
                throw ОшибкаКомандногоИсполнения.записьПовтора
            }
            return (определение, канонические, try значение(принято))
        }
        let наблюдение = try измерить("исполнение") {
            try AutomationExecutor.выполнить(определение.0, вход: определение.2,
                пределы: принято.профиль.пределы, профиль: профиль == nil ? nil : { замер in
                    профиль?(МеткаИсполнения(стадия: "интерпретатор/" + замер.стадия,
                        наносекунды: замер.наносекунды, исход: замер.исход, глубина: 1))
                })
        }
        if let хэш = подготовка.хэшПовтора, хэш != наблюдение.хэшНаблюдения {
            throw ОшибкаКомандногоИсполнения.расхождениеПовтора
        }
        return try измерить("сохранение") {
            let запись = ЗаписьИсполнения(принятыеДанные: ПринятыеДанные(
                исходноеОпределение: принято.исходноеОпределение, определение: определение.1,
                вход: принято.вход, типВхода: принято.типВхода, профиль: принято.профиль), наблюдение: наблюдение)
            let данные = try кодировать(запись)
            let описание = ОписаниеНаблюдения(идентификатор: UUID().uuidString.lowercased(),
                тип: "исполнение-оператора", источник: "FUMA",
                время: ISO8601DateFormatter().string(from: Date()),
                спецификация: try кодировать(принято.профиль))
            let сегмент = try Сегмент(кореньДанных: подготовка.каталог, запись: true,
                операции: операции, профилировать: профиль != nil)
            defer {
                for метка in сегмент.профиль {
                    профиль?(МеткаИсполнения(стадия: "контейнер/" + метка.этап,
                        наносекунды: метка.наносекунды, исход: метка.исход, глубина: метка.глубина + 1))
                }
                сегмент.закрыть()
            }
            let квитанция = try сегмент.добавить(описание, данные: данные)
            return try кодировать(ОтветИсполнения(квитанция: квитанция, наблюдение: наблюдение))
        }
    }

    private struct Подготовка {
        let каталог: URL
        let данные: ПринятыеДанные
        let каноническое: Data?
        let хэшПовтора: String?
    }

    private static func принять(_ аргументы: [String]) throws -> Подготовка {
        var значения: [String: String] = [:]
        var флаги = Set<String>()
        var номер = 0
        while номер < аргументы.count {
            let имя = аргументы[номер]
            if имя == "--выполнить-оператор" || имя == "--профиль" {
                guard флаги.insert(имя).inserted else { throw ОшибкаКомандногоИсполнения.аргументы }
                номер += 1
            } else {
                guard параметры.contains(имя) || имя == "--повторить-оператор",
                    номер + 1 < аргументы.count, значения[имя] == nil,
                    !аргументы[номер + 1].isEmpty, !аргументы[номер + 1].hasPrefix("--")
                else { throw ОшибкаКомандногоИсполнения.аргументы }
                значения[имя] = аргументы[номер + 1]
                номер += 2
            }
        }
        guard let путь = значения["--журнал"] else { throw ОшибкаКомандногоИсполнения.аргументы }
        _ = try ПутиПриложения.внешнийКаталог(путь)
        guard let физический = realpath(путь, nil) else { throw ОшибкаКомандногоИсполнения.приватныйКаталог }
        defer { free(физический) }
        let каталог = URL(fileURLWithPath: String(cString: физический))
        // Существующий приватный каталог выбирается явно. Создание и восстановление истории отдельны.
        guard каталог.path == URL(fileURLWithPath: путь).path,
            let права = try FileManager.default.attributesOfItem(atPath: каталог.path)[.posixPermissions] as? NSNumber,
            права.intValue & 0o077 == 0 else { throw ОшибкаКомандногоИсполнения.приватныйКаталог }
        if let идентификатор = значения["--повторить-оператор"] {
            guard !флаги.contains("--выполнить-оператор"), Set(значения.keys) == ["--повторить-оператор", "--журнал"]
            else { throw ОшибкаКомандногоИсполнения.аргументы }
            let сегмент = try Сегмент(кореньДанных: каталог, запись: false, создать: false)
            defer { сегмент.закрыть() }
            guard let квитанция = сегмент.записи.first(where: { $0.описание.идентификатор == идентификатор }),
                квитанция.описание.тип == "исполнение-оператора", квитанция.описание.версияСхемы == 1,
                квитанция.описание.источник == "FUMA" else { throw ОшибкаКомандногоИсполнения.записьПовтора }
            let запись = try JSONDecoder().decode(ВходПовтора.self, from: сегмент.извлечь(идентификатор))
            guard запись.схема == "fuma.исполнение-оператора.1" else { throw ОшибкаКомандногоИсполнения.записьПовтора }
            return Подготовка(каталог: каталог, данные: запись.принятыеДанные,
                каноническое: запись.принятыеДанные.определение, хэшПовтора: запись.наблюдение.хэшНаблюдения)
        }
        guard флаги.contains("--выполнить-оператор"), Set(значения.keys) == параметры,
            let вид = ВидВхода(rawValue: значения["--тип-входа"]!) else { throw ОшибкаКомандногоИсполнения.аргументы }
        let определение = try прочитатьВход(значения["--определение"]!, предел: 65_536)
        let вход = try прочитатьВход(значения["--вход"]!, предел: ПрофильИсполнителя.текущий.байтовВхода)
        return Подготовка(каталог: каталог, данные: ПринятыеДанные(
            исходноеОпределение: определение, определение: Data(), вход: вход, типВхода: вид, профиль: .текущий),
            каноническое: nil, хэшПовтора: nil)
    }

    private static func значение(_ данные: ПринятыеДанные) throws -> ЗначениеОператора {
        guard данные.вход.count <= данные.профиль.байтовВхода else { throw ОшибкаКонтейнера.предел }
        switch данные.типВхода {
        case .байты: return .байты(Array(данные.вход))
        case .текст:
            guard let текст = String(data: данные.вход, encoding: .utf8) else { throw ОшибкаКомандногоИсполнения.кодировка }
            return .текст(текст)
        }
    }

    private static func кодировать<Значение: Encodable>(_ значение: Значение) throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        var данные = try кодировщик.encode(значение)
        данные.append(10)
        return данные
    }
}


import CryptoKit
import Foundation
import Testing
@testable import ПрофильСохраняющейКонтрольнойТочки

@Suite struct ПроверкаTests {
    private let источник = Data("явное ROOT разрешение на профиль".utf8)
    private let кореньWorktree = "fixture-worktree-root"

    @Test func принимаетУзкийПрофильСЯвноНезапущеннымиПроверками() throws {
        let профиль = try JSONEncoder().encode(образец())
        let результат = try ПроверкаСохраняющегоПрофиля.проверить(
            профиль,
            источник: источник,
            кореньWorktree: кореньWorktree
        )
        #expect(результат.схема == ПроверкаСохраняющегоПрофиля.схема)
        #expect(результат.проверки["root_jsonl"]?.исход == .неЗапускалось)
    }

    @Test func отклоняетФиктивныйУспехИсключённойПроверки() throws {
        let образец = образец()
        let профиль = ПрофильСнимка(
            схема: образец.схема,
            грант: ГрантПрофиля(
                корневойUUID: образец.грант.корневойUUID,
                основаниеSHA256: образец.грант.основаниеSHA256,
                область: образец.грант.область,
                писателей: 1,
                остановкаСохранена: true
            ),
            основа: образец.основа,
            автор: образец.автор,
            модель: образец.модель,
            проверки: [
                "native_swift_positive": .init(исход: .выполнено, основание: "положительный случай"),
                "native_swift_negative": .init(исход: .выполнено, основание: "отрицательный случай"),
                "legacy_python": .init(исход: .неЗапускалось, основание: "прямой запрет"),
                "root_jsonl": .init(исход: .выполнено, основание: "неверно объявлено GREEN"),
                "publication": .init(исход: .неизвестно, основание: "не проверено")
            ],
            неизвестныйОстаток: образец.неизвестныйОстаток
        )
        let данные = try JSONEncoder().encode(профиль)
        #expect(throws: ОшибкаПрофиля.self) {
            try ПроверкаСохраняющегоПрофиля.проверить(
                данные,
                источник: источник,
                кореньWorktree: кореньWorktree
            )
        }
    }

    private func образец() -> ПрофильСнимка {
        let hash = SHA256.hash(data: источник).map { String(format: "%02x", $0) }.joined()
        let worktreeHash = SHA256.hash(data: Data(кореньWorktree.utf8)).map { String(format: "%02x", $0) }.joined()
        let проверки: [String: ЗаписьПроверки] = [
            "native_swift_positive": .init(исход: .выполнено, основание: "положительный случай"),
            "native_swift_negative": .init(исход: .выполнено, основание: "отрицательный случай"),
            "legacy_python": .init(исход: .неЗапускалось, основание: "прямой запрет"),
            "root_jsonl": .init(исход: .неЗапускалось, основание: "прямой запрет"),
            "publication": .init(исход: .неизвестно, основание: "не проверено")
        ]
        return ПрофильСнимка(
            схема: ПроверкаСохраняющегоПрофиля.схема,
            грант: ГрантПрофиля(
                корневойUUID: "01a07d3d-d376-7ad2-aafc-67e4c25a67eb",
                основаниеSHA256: hash,
                область: ["AGENTS.md", "Правила/агентов/журнал-и-происхождение.md"],
                писателей: 1,
                остановкаСохранена: true
            ),
            основа: GitОснова(
                commit: "9eec7d2f1f9f49b09812963f68ed637e96850090",
                tree: "869f19a1edea79dbf6652570834f477619ae4bbe",
                ref: "refs/heads/codex/preserving-profile",
                кореньWorktreeSHA256: worktreeHash
            ),
            автор: "неизвестно",
            модель: "неизвестно",
            проверки: проверки,
            неизвестныйОстаток: ["полный ROOT JSONL и старые Python-проверки намеренно не запускались"]
        )
    }
}

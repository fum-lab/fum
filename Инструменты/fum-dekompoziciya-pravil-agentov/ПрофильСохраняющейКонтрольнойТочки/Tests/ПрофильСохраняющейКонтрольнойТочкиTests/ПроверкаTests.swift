import CryptoKit
import Foundation
import Testing
@testable import ПрофильСохраняющейКонтрольнойТочки

@Suite struct ПроверкаTests {
    private let источник = Data("явное ROOT разрешение на профиль".utf8)
    private let кореньWorktree = "fixture-worktree-root"
    private let кореньRootWorktree = "fixture-root-worktree"
    private let корневойUUID = "01a07d3d-d376-7ad2-aafc-67e4c25a67eb"
    private let собственныйUUID = "01a17869-c953-7163-bb76-21716549be02"

    @Test func принимаетУзкийПрофильСЯвноНезапущеннымиПроверками() throws {
        let строка = строкаМодели(uuid: собственныйUUID, модель: "gpt-5.6-sol", усилие: "ultra", корень: кореньWorktree)
        let профиль = try JSONEncoder().encode(образец(собственнаяСтрока: строка))
        let результат = try ПроверкаСохраняющегоПрофиля.проверить(
            профиль,
            источник: источник,
            собственныйNativeUUID: собственныйUUID,
            собственнаяСтрока: строка,
            кореньWorktree: кореньWorktree
        )
        #expect(результат.схема == ПроверкаСохраняющегоПрофиля.схема)
        #expect(результат.собственныйNativeUUID == собственныйUUID)
        #expect(результат.проверки["root_jsonl"]?.исход == .неЗапускалось)
    }

    @Test func отклоняетПолностьюСогласованнуюПодстановкуКорневогоUUID() throws {
        let строкаКорня = строкаМодели(
            uuid: корневойUUID,
            модель: "gpt-6.1-sol",
            усилие: "ultra",
            корень: кореньRootWorktree
        )
        let подмена = образец(
            собственныйUUID: корневойUUID,
            модель: "gpt-6.1-sol",
            усилие: "ultra",
            кореньПрофиля: кореньRootWorktree,
            собственнаяСтрока: строкаКорня
        )
        let данные = try JSONEncoder().encode(подмена)

        do {
            _ = try ПроверкаСохраняющегоПрофиля.проверить(
                данные,
                источник: источник,
                собственныйNativeUUID: корневойUUID,
                собственнаяСтрока: строкаКорня,
                кореньWorktree: кореньRootWorktree
            )
            Issue.record("полностью согласованная подстановка корневого UUID должна быть отклонена")
        } catch let ошибка as ОшибкаПрофиля {
            #expect(ошибка.причина == "корневой UUID подменил собственный native UUID источника")
        }
    }

    @Test func отклоняетДругойВалидныйOIDВКоррекции() throws {
        let строка = строкаМодели(uuid: собственныйUUID, модель: "gpt-5.6-sol", усилие: "ultra", корень: кореньWorktree)
        let профиль = try JSONEncoder().encode(образец(
            ошибочныйКоммит: String(repeating: "a", count: 40),
            собственнаяСтрока: строка
        ))

        do {
            _ = try ПроверкаСохраняющегоПрофиля.проверить(
                профиль,
                источник: источник,
                собственныйNativeUUID: собственныйUUID,
                собственнаяСтрока: строка,
                кореньWorktree: кореньWorktree
            )
            Issue.record("коррекция должна быть привязана к точному ошибочному коммиту")
        } catch let ошибка as ОшибкаПрофиля {
            #expect(ошибка.причина == "коррекция происхождения не связана с собственной SQLite-строкой")
        }
    }

    @Test func отклоняетФиктивныйУспехИсключённойПроверки() throws {
        let строка = строкаМодели(uuid: собственныйUUID, модель: "gpt-5.6-sol", усилие: "ultra", корень: кореньWorktree)
        let образец = образец(собственнаяСтрока: строка)
        let профиль = ПрофильСнимка(
            схема: образец.схема,
            собственныйNativeUUID: образец.собственныйNativeUUID,
            грант: ГрантПрофиля(
                корневойUUID: образец.грант.корневойUUID,
                основаниеSHA256: образец.грант.основаниеSHA256,
                область: образец.грант.область,
                писателей: 1,
                остановкаСохранена: true
            ),
            основа: образец.основа,
            автор: образец.автор,
            модель: образец.модель,
            коррекцияПроисхождения: образец.коррекцияПроисхождения,
            проверки: [
                "native_swift_positive": .init(исход: .выполнено, основание: "положительный случай"),
                "native_swift_negative": .init(исход: .выполнено, основание: "отрицательный случай"),
                "legacy_python": .init(исход: .неЗапускалось, основание: "прямой запрет"),
                "root_jsonl": .init(исход: .выполнено, основание: "неверно объявлено GREEN"),
                "publication": .init(исход: .неизвестно, основание: "не проверено")
            ],
            неизвестныйОстаток: образец.неизвестныйОстаток
        )
        let данные = try JSONEncoder().encode(профиль)
        #expect(throws: ОшибкаПрофиля.self) {
            try ПроверкаСохраняющегоПрофиля.проверить(
                данные,
                источник: источник,
                собственныйNativeUUID: собственныйUUID,
                собственнаяСтрока: строка,
                кореньWorktree: кореньWorktree
            )
        }
    }

    private func образец(
        собственныйUUID: String? = nil,
        модель: String = "gpt-5.6-sol",
        усилие: String = "ultra",
        кореньПрофиля: String? = nil,
        ошибочныйКоммит: String = "f51640731bba74b4150ce1abbce84b120a41d77f",
        собственнаяСтрока: Data
    ) -> ПрофильСнимка {
        let выбранныйUUID = собственныйUUID ?? self.собственныйUUID
        let выбранныйКорень = кореньПрофиля ?? кореньWorktree
        let hash = SHA256.hash(data: источник).map { String(format: "%02x", $0) }.joined()
        let worktreeHash = SHA256.hash(data: Data(выбранныйКорень.utf8)).map { String(format: "%02x", $0) }.joined()
        let строкаHash = SHA256.hash(data: собственнаяСтрока).map { String(format: "%02x", $0) }.joined()
        let проверки: [String: ЗаписьПроверки] = [
            "native_swift_positive": .init(исход: .выполнено, основание: "положительный случай"),
            "native_swift_negative": .init(исход: .выполнено, основание: "отрицательный случай"),
            "legacy_python": .init(исход: .неЗапускалось, основание: "прямой запрет"),
            "root_jsonl": .init(исход: .неЗапускалось, основание: "прямой запрет"),
            "publication": .init(исход: .неизвестно, основание: "не проверено")
        ]
        return ПрофильСнимка(
            схема: ПроверкаСохраняющегоПрофиля.схема,
            собственныйNativeUUID: выбранныйUUID,
            грант: ГрантПрофиля(
                корневойUUID: корневойUUID,
                основаниеSHA256: hash,
                область: ["AGENTS.md", "Правила/агентов/журнал-и-происхождение.md"],
                писателей: 1,
                остановкаСохранена: true
            ),
            основа: GitОснова(
                commit: "9eec7d2f1f9f49b09812963f68ed637e96850090",
                tree: "869f19a1edea79dbf6652570834f477619ae4bbe",
                ref: "refs/heads/codex/preserving-profile",
                кореньWorktreeSHA256: worktreeHash
            ),
            автор: "FUM Codex [\(модель); effort=\(усилие)]",
            модель: модель,
            коррекцияПроисхождения: КоррекцияПроисхождения(
                ошибочныйКоммит: ошибочныйКоммит,
                ошибочноВыбранныйNativeUUID: корневойUUID,
                собственнаяМодель: модель,
                собственноеУсилие: усилие,
                проекцияАвтора: "FUM Codex [\(модель); effort=\(усилие)]",
                строкаSHA256: строкаHash,
                байтыВнеGit: "sessions/fixture/own-model-observation.tsv",
                историческийBackend: "неизвестно"
            ),
            проверки: проверки,
            неизвестныйОстаток: ["полный ROOT JSONL и старые Python-проверки намеренно не запускались"]
        )
    }

    private func строкаМодели(uuid: String, модель: String, усилие: String, корень: String) -> Data {
        Data("\(uuid)\t\(модель)\t\(усилие)\t\(корень)\n".utf8)
    }
}

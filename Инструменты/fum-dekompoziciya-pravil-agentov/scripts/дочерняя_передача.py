"""Согласованность декларации конечной передачи и её действующих норм."""

import re


ПРАВИЛО = "FUM-ПРАВИЛО-НОВОЕ-000019"
ОСНОВАНИЕ = "FUM-ПРАВИЛО-000061"
ТЕМА = "Правила/агентов/проверки-коммит-и-публикация.md"
КОНВЕЙЕР = "Инструменты/fum-konvejyer-proizvodnyikh-vetok/scripts/"
ДЕКЛАРАЦИЯ = {
    "режим": "дочерняя-передача",
    "правило": ПРАВИЛО,
    "корневое_основание": ОСНОВАНИЕ,
    "получить_назначение": КОНВЕЙЕР + "получить-назначение.py",
    "проверить_передачу": КОНВЕЙЕР + "дочерний_коммит.py",
    "подготовить_окружение": КОНВЕЙЕР + "подготовить-окружение-слоя.py",
    "проверить_связность": КОНВЕЙЕР + "связность_слоя.py",
    "создать_коммит": "Инструменты/fum-svyaznostj-rabochej-sessii/scripts/создание_коммита.py",
}


def проверить(корень, текст, манифест, правила, профиль, проверить_путь, ошибка):
    """Проверяет регистрацию и локальные пути, но не доказывает смысл текста норм."""
    if ("дочерняя_передача" not in манифест and ПРАВИЛО not in правила
            and "НОВОЕ-000019" not in текст):
        return
    if манифест.get("дочерняя_передача") != ДЕКЛАРАЦИЯ:
        raise ошибка("дочерняя передача: требуется точная согласованная декларация")
    if профиль != "JSONL":
        raise ошибка("дочерняя передача требует полного корневого профиля JSONL")
    for идентификатор, приоритет, путь in (
            (ОСНОВАНИЕ, "P0-ядро", "AGENTS.md"),
            (ПРАВИЛО, "P1-сессия", ТЕМА)):
        правило = правила.get(идентификатор, {})
        if (правило.get("статус") != "действует"
                or правило.get("приоритет") != приоритет
                or правило.get("назначение") != {"путь": путь, "якорь": идентификатор}):
            raise ошибка("дочерняя передача требует действующих норм P0 и P1")
    якоря = list(re.finditer(r"^<!-- FUM-ПРАВИЛО: ([^\n]+) -->\n", текст, re.MULTILINE))
    номера = [i for i, якорь in enumerate(якоря) if якорь.group(1) == ОСНОВАНИЕ]
    if len(номера) != 1:
        raise ошибка("дочерняя передача требует единственного корневого основания")
    номер = номера[0]
    конец = якоря[номер + 1].start() if номер + 1 < len(якоря) else len(текст)
    тело = текст[якоря[номер].end():конец]
    тело = re.sub(r"<!--.*?-->", "", тело, flags=re.DOTALL)
    if "`дочерняя-передача`" not in тело or "НОВОЕ-000019" not in тело:
        raise ошибка("дочерняя передача не названа в корневом основании")
    for ключ in ("получить_назначение", "проверить_передачу", "проверить_связность", "создать_коммит", "подготовить_окружение"):
        проверить_путь(корень, ДЕКЛАРАЦИЯ[ключ])

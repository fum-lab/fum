def видимый_текст_нормы(текст):
    """Только закрытые spans одной строки с равными полными сериями кавычек."""
    if '\\`' in текст:
        raise ОшибкаПроверки('неподдержанные экранированные кавычки в норме автора')
    строки = []
    for строка in текст.splitlines():
        серии = list(re.finditer(r'`+', строка))
        части = []; начало = 0; номер = 0
        while номер < len(серии):
            открытие = серии[номер]
            закрытие = next((н for н in range(номер + 1, len(серии))
                if len(серии[н].group()) == len(открытие.group())), None)
            if закрытие is None:
                raise ОшибкаПроверки('непарные или межстрочные кавычки в норме автора')
            части.append(строка[начало:открытие.start()])
            начало = серии[закрытие].end(); номер = закрытие + 1
        части.append(строка[начало:]); строки.append(''.join(части))
    return '\n'.join(строки)



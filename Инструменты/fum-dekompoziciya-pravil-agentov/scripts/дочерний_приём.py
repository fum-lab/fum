"""Проверяемое включение адресного приёма без ослабления обязанностей корня."""
import re

from дочерняя_передача import ДЕКЛАРАЦИЯ as ДЕКЛАРАЦИЯ_ПЕРЕДАЧИ

ПРАВИЛО = 'FUM-ПРАВИЛО-НОВОЕ-000021'
ОСНОВАНИЕ = 'FUM-ПРАВИЛО-000061'
ТЕМА = 'Правила/агентов/проверки-коммит-и-публикация.md'
КОНВЕЙЕР = 'Инструменты/fum-konvejyer-proizvodnyikh-vetok/scripts/'
ДЕКЛАРАЦИЯ = {
    'режим': 'дочерний-приём', 'правило': ПРАВИЛО, 'корневое_основание': ОСНОВАНИЕ,
    'принять_поручение': КОНВЕЙЕР + 'приём_получателя.py',
    'проверить_назначение': КОНВЕЙЕР + 'приём_интеграции.py',
    'обновить_свежесть': КОНВЕЙЕР + 'свежесть_приёма.py',
    'проверить_связность': КОНВЕЙЕР + 'связность_приёма.py',
    'проверить_коммит': КОНВЕЙЕР + 'коммит_приёма.py',
    'создать_коммит': 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/создание_коммита.py',
}


def проверить(корень, текст, манифест, правила, профиль, проверить_путь, ошибка):
    if ('дочерний_приём' not in манифест and ПРАВИЛО not in правила
            and 'НОВОЕ-000021' not in текст and 'дочерний-приём' not in текст):
        return
    if манифест.get('дочерний_приём') != ДЕКЛАРАЦИЯ:
        raise ошибка('дочерний приём: требуется точная согласованная декларация')
    if профиль != 'JSONL' or манифест.get('дочерняя_передача') != ДЕКЛАРАЦИЯ_ПЕРЕДАЧИ:
        raise ошибка('дочерний приём требует корневого профиля JSONL и исходной передачи')
    for идентификатор, приоритет, путь in (
            (ОСНОВАНИЕ, 'P0-ядро', 'AGENTS.md'), (ПРАВИЛО, 'P1-сессия', ТЕМА)):
        правило = правила.get(идентификатор, {})
        if (правило.get('статус') != 'действует' or правило.get('приоритет') != приоритет
                or правило.get('назначение') != {'путь': путь, 'якорь': идентификатор}):
            raise ошибка('дочерний приём требует действующих норм P0 и P1')
    якоря = list(re.finditer(r'^<!-- FUM-ПРАВИЛО: ([^\n]+) -->\n', текст, re.MULTILINE))
    номера = [номер for номер, якорь in enumerate(якоря) if якорь.group(1) == ОСНОВАНИЕ]
    if len(номера) != 1:
        raise ошибка('дочерний приём требует единственного корневого основания')
    номер = номера[0]
    конец = якоря[номер + 1].start() if номер + 1 < len(якоря) else len(текст)
    тело = re.sub(r'<!--.*?-->', '', текст[якоря[номер].end():конец], flags=re.DOTALL)
    if '`дочерний-приём`' not in тело or 'НОВОЕ-000021' not in тело:
        raise ошибка('дочерний приём не назван в корневом основании')
    for ключ, значение in ДЕКЛАРАЦИЯ.items():
        if ключ not in {'режим', 'правило', 'корневое_основание'}:
            проверить_путь(корень, значение)

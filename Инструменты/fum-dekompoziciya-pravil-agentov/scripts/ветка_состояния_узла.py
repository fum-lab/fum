def тело_правила(текст, идентификатор, ошибка):
    # Поддержанный профиль не прячет нормы в оградах или HTML-областях.
    if '\\`' in текст:
        raise ошибка('ветка состояния: неподдержанные экранированные кавычки')
    for строка in текст.splitlines():
        if re.match(r'^[ \t]*(?:`{3,}|\x7e{3,})', строка):
            raise ошибка('ветка состояния: скрытая ограждённая норма')
        if '<!--' in строка or '-->' in строка:
            if not (строка.startswith('<!-- ') and строка.endswith(' -->')
                    and строка.count('<!--') == 1 and строка.count('-->') == 1):
                raise ошибка('ветка состояния: скрытая HTML-норма')
        elif re.match(r'^[ \t]*<(?:/?[A-Za-z]|[!?])', строка):
            raise ошибка('ветка состояния: скрытая HTML-область')
        # Вырезаются только закрытые spans одной строки с равными полными
        # сериями кавычек. Межстрочный span мог бы скрыть неизменный якорь.
        серии = list(re.finditer(r'`+', строка))
        части = []; начало = 0; номер = 0
        while номер < len(серии):
            открытие = серии[номер]
            закрытие = next((н for н in range(номер + 1, len(серии))
                if len(серии[н].group()) == len(открытие.group())), None)
            if закрытие is None:
                raise ошибка('ветка состояния: непарные или межстрочные кавычки')
            части.append(строка[начало:открытие.start()])
            начало = серии[закрытие].end(); номер = закрытие + 1
        части.append(строка[начало:])
        видимое = ''.join(части)
        if (re.search(r'<(?:/?[A-Za-z]|[!?])', видимое)
                and not re.fullmatch(r'<!-- [^\n]* -->', видимое)):
            raise ошибка('ветка состояния: скрытая встроенная HTML-область')
    якоря = list(re.finditer(r'^<!-- FUM-ПРАВИЛО: ([^\n]+) -->\n', текст, re.MULTILINE))
    номера = [н for н, я in enumerate(якоря) if я.group(1) == идентификатор]
    if len(номера) != 1:
        raise ошибка('ветка состояния: нужен единственный полный якорь')
    н = номера[0]
    конец = якоря[н+1].start() if н+1 < len(якоря) else len(текст)
    return текст[якоря[н].end():конец].rstrip('\n')



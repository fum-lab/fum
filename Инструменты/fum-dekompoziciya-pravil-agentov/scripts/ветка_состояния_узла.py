def тело_правила(текст, идентификатор, ошибка):
    # Поддержанный профиль не прячет нормы в оградах или HTML-областях.
    for строка in текст.splitlines():
        if re.match(r'^[ \t]*(?:`{3,}|\x7e{3,})', строка):
            raise ошибка('ветка состояния: скрытая ограждённая норма')
        if '<!--' in строка or '-->' in строка:
            if not (строка.startswith('<!-- ') and строка.endswith(' -->')
                    and строка.count('<!--') == 1 and строка.count('-->') == 1):
                raise ошибка('ветка состояния: скрытая HTML-норма')
        elif re.match(r'^[ \t]*<', строка):
            raise ошибка('ветка состояния: скрытая HTML-область')
    якоря = list(re.finditer(r'^<!-- FUM-ПРАВИЛО: ([^\n]+) -->\n', текст, re.MULTILINE))
    номера = [н for н, я in enumerate(якоря) if я.group(1) == идентификатор]
    if len(номера) != 1:
        raise ошибка('ветка состояния: нужен единственный полный якорь')
    н = номера[0]
    конец = якоря[н+1].start() if н+1 < len(якоря) else len(текст)
    return текст[якоря[н].end():конец].rstrip('\n')



"""Точный нормативный допуск одной ветки состояния; без runtime-эффектов."""
import copy
import json
from pathlib import Path
import unittest

from test_декомпозиция_правил_агентов import ПроверкаДекомпозицииПравил, КОРЕНЬ_ИНСТРУМЕНТА, хэш_текста

ПРАВИЛО = 'FUM-ПРАВИЛО-НОВОЕ-000023'
ОСНОВАНИЕ = 'FUM-ПРАВИЛО-000058'
ТЕМА = 'Правила/агентов/Git-и-рабочая-сессия.md'


class ВеткаСостояния(ПроверкаДекомпозицииПравил):
    def включить_состояние(это):
        м = это.включить_границу_сообщений()
        ф = json.loads((КОРЕНЬ_ИНСТРУМЕНТА/'tests/фикстуры/профиль-ветки-состояния.json').read_bytes())
        р = это.корень/'AGENTS.md'
        р.write_text(р.read_text()+'\n<!-- FUM-ПРАВИЛО: '+ОСНОВАНИЕ+' -->\n'+ф['тела'][ОСНОВАНИЕ]+'\n')
        т = это.корень/ТЕМА
        т.write_text(т.read_text()+'\n<!-- FUM-ПРАВИЛО: '+ПРАВИЛО+' -->\n'+ф['тела'][ПРАВИЛО]+'\n')
        for и,п,путь in ((ОСНОВАНИЕ,'P0-ядро','AGENTS.md'),(ПРАВИЛО,'P1-сессия',ТЕМА)):
            м['правила'].append({'идентификатор':и,'статус':'действует','приоритет':п,
                'области':['сессия'],'триггеры':['git'],'семантический_ключ':и,
                'назначение':{'путь':путь,'якорь':и},'источники':[],'новое_основание':'AGENTS.md'})
        м['ветка_состояния_узла'] = copy.deepcopy(ф['декларация'])
        for к,путь in м['ветка_состояния_узла'].items():
            if к in ('проверить_полномочия','проверить_ACT','обновить_ожидания','создать_коммит'):
                это.записать(путь,'raise RuntimeError("нормативный валидатор не запускает runtime")\n')
        это.обновить_тему(м)
        return м

    def обновить_тему(это,м):
        for т in м['темы']:
            if т['путь']==ТЕМА:
                т['sha256_содержания']=хэш_текста((это.корень/ТЕМА).read_text())
        это.сохранить_манифест(м)

    def test_состояние_принимает_точный_профиль(это):
        это.включить_состояние()
        р=это.запустить('проверить')
        это.assertEqual(р.returncode,0,р.stderr)

    def test_состояние_не_выключается_удалением_части_допуска(это):
        for часть in ('декларация','правило','указатель'):
            with это.subTest(часть=часть):
                м=это.включить_состояние()
                if часть=='декларация': del м['ветка_состояния_узла']
                elif часть=='правило': м['правила']=[э for э in м['правила'] if э['идентификатор']!=ПРАВИЛО]
                else:
                    п=это.корень/'AGENTS.md';п.write_text(п.read_text().replace(', `НОВОЕ-000023` (ветка состояния узла)',''))
                это.сохранить_манифест(м)
                это.потребовать_отказ('состояни')

    def test_состояние_закрывает_каждое_поле_декларации(это):
        for ключ in json.loads((КОРЕНЬ_ИНСТРУМЕНТА/'tests/фикстуры/профиль-ветки-состояния.json').read_bytes())['декларация']:
            with это.subTest(ключ=ключ):
                м=это.включить_состояние();м['ветка_состояния_узла'][ключ]+='-другой'
                это.сохранить_манифест(м);это.потребовать_отказ('состояни')
        for вид in ('лишнее','нет-поля'):
            with это.subTest(вид=вид):
                м=это.включить_состояние()
                if вид=='лишнее': м['ветка_состояния_узла']['лишнее']=True
                else: del м['ветка_состояния_узла']['ветка']
                это.сохранить_манифест(м);это.потребовать_отказ('состояни')

    def test_состояние_отклоняет_повторный_JSON_ключ(это):
        это.включить_состояние();п=это.корень/'Правила/агентов/инвентарь-правил.json'
        п.write_text(п.read_text().replace('"ветка_ROOT":','"ветка_ROOT": "refs/heads/fuma", "ветка_ROOT":',1))
        это.потребовать_отказ('повтор ключа')

    def test_состояние_требует_действующие_точные_назначения(это):
        for и in (ПРАВИЛО,ОСНОВАНИЕ):
            for к,в in (('статус','контекст'),('приоритет','P2-тема'),('назначение',{'путь':ТЕМА,'якорь':'другой'})):
                with это.subTest(правило=и,поле=к):
                    м=это.включить_состояние()
                    next(э for э in м['правила'] if э['идентификатор']==и)[к]=в
                    это.сохранить_манифест(м);это.потребовать_отказ('состояни')

    def test_состояние_не_саморазрешается_новым_SHA_темы(это):
        изменения=('одного писателя','независимый ACT','не создаёт второй коммит','ROOT остаётся','не активирует FIFO')
        for ч in изменения:
            with это.subTest(часть=ч):
                м=это.включить_состояние();п=это.корень/ТЕМА;п.write_text(п.read_text().replace(ч,'иная граница'))
                это.обновить_тему(м);это.потребовать_отказ('состояни')

    def test_состояние_не_принимает_скрытые_тела(это):
        for путь,и in (('AGENTS.md',ОСНОВАНИЕ),(ТЕМА,ПРАВИЛО)):
            for начало,конец in (('<!--\n','\n-->'),('```text\n','\n```'),('<div>\n','\n</div>')):
                with это.subTest(путь=путь,область=начало):
                    м=это.включить_состояние();п=это.корень/путь;т=п.read_text();маркер='<!-- FUM-ПРАВИЛО: '+и+' -->\n'
                    п.write_text(т.replace(маркер,начало+маркер,1)+конец+'\n')
                    это.обновить_тему(м);это.потребовать_отказ('состояни' if путь==ТЕМА else 'скрыт')

    def test_состояние_требует_физические_пути_без_symlink(это):
        for к in ('проверить_полномочия','проверить_ACT','обновить_ожидания','создать_коммит'):
            for вид in ('отсутствует','symlink'):
                with это.subTest(путь=к,вид=вид):
                    м=это.включить_состояние();п=это.корень/м['ветка_состояния_узла'][к];п.unlink()
                    if вид=='symlink': п.symlink_to(это.корень/'AGENTS.md')
                    это.потребовать_отказ('не найден' if вид=='отсутствует' else 'символической')

    def test_состояние_сохраняет_полный_ROOT_профиль(это):
        м=это.включить_состояние();м['продолжение_задачи']['обязательные_параметры']=['--перед-завершением']
        это.сохранить_манифест(м);это.потребовать_отказ('продолжени')


def load_tests(loader, tests, pattern):
    имена=[и for и in loader.getTestCaseNames(ВеткаСостояния) if и.startswith('test_состояние_')]
    return unittest.TestSuite(ВеткаСостояния(и) for и in имена)

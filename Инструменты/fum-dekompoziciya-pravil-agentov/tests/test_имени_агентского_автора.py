"""Семантический допуск имени не расширяется обновлением SHA темы."""
import copy
import json
from pathlib import Path
import re
import unittest

import test_декомпозиция_правил_агентов as база

ПРАВИЛО = 'FUM-ПРАВИЛО-000063'
ТЕМА = 'Правила/агентов/Git-и-рабочая-сессия.md'
КАТАЛОГ = 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/'
ДЕКЛАРАЦИЯ = {'правило': ПРАВИЛО, 'роль': 'FUM Codex',
    'автор': КАТАЛОГ + 'автор_коммита.py', 'создатель': КАТАЛОГ + 'создание_коммита.py',
    'подготовитель': КАТАЛОГ + 'подготовка_дочернего_поручения.py'}


class ИмяАгентскогоАвтора(unittest.TestCase):
    def setUp(сам):
        сам.стенд = база.ПроверкаДекомпозицииПравил()
        сам.стенд.подготовить_стенд()
        сам.addCleanup(сам.стенд.doCleanups)
        сам.корень = сам.стенд.корень

    def включить(сам):
        сам.стенд.создать_корректный_стенд()
        м = json.loads((сам.корень / 'Правила/агентов/инвентарь-правил.json').read_bytes())
        настоящий = (база.КОРЕНЬ_ИНСТРУМЕНТА.parents[1] / ТЕМА).read_text()
        тело = re.search(r'<!-- FUM-ПРАВИЛО: FUM-ПРАВИЛО-000063 -->\n(.*?)(?=\n<!-- FUM-ПРАВИЛО:)', настоящий, re.S)[1].rstrip('\n')
        сам.стенд.записать(ТЕМА, (сам.корень / ТЕМА).read_text() + '\n<!-- FUM-ПРАВИЛО: '+ПРАВИЛО+' -->\n'+тело+'\n')
        м['правила'].append({'идентификатор': ПРАВИЛО, 'статус': 'действует', 'приоритет': 'P1-сессия',
            'области': ['сессия'], 'триггеры': ['публикация'], 'семантический_ключ': 'автор-Codex',
            'назначение': {'путь': ТЕМА, 'якорь': ПРАВИЛО}, 'источники': [], 'новое_основание': 'AGENTS.md'})
        м['имя_агентского_автора'] = copy.deepcopy(ДЕКЛАРАЦИЯ)
        for ключ in ('автор', 'создатель', 'подготовитель'):
            сам.стенд.записать(ДЕКЛАРАЦИЯ[ключ], 'raise RuntimeError("Нормативная проверка не исполняет Creator")\n')
        сам.сохранить(м)
        return м

    def сохранить(сам, м):
        for тема in м['темы']:
            if тема['путь'] == ТЕМА: тема['sha256_содержания'] = база.хэш_текста((сам.корень / ТЕМА).read_text())
        сам.стенд.сохранить_манифест(м)

    def отказ(сам):
        р = сам.стенд.запустить('проверить')
        сам.assertNotEqual(0, р.returncode, р.stdout)
        сам.assertIn('автор', р.stderr.lower())

    def test_точное_имя_и_тело_нормы_допускаются(сам):
        сам.включить(); р = сам.стенд.запустить('проверить')
        сам.assertEqual(0, р.returncode, р.stderr)

    def test_разметка_в_буквальном_коде_не_прячет_норму(сам):
        for кавычки in ('`', '``'):
            with сам.subTest(кавычки=кавычки):
                м = сам.включить(); файл = сам.корень / ТЕМА
                файл.write_text('Пример '+кавычки+'<div hidden>'+кавычки+' остаётся кодом.\n'+файл.read_text())
                сам.сохранить(м); р = сам.стенд.запустить('проверить')
                сам.assertEqual(0, р.returncode, р.stderr)

    def test_роль_не_узаконивается_новым_SHA_темы(сам):
        м = сам.включить(); файл = сам.корень / ТЕМА
        файл.write_text(файл.read_text().replace('FUM Codex', 'FUM Разработчик'))
        сам.сохранить(м); сам.отказ()

    def test_декларация_не_удаляется_частично(сам):
        м = сам.включить(); del м['имя_агентского_автора']; сам.сохранить(м); сам.отказ()

    def test_все_поля_декларации_закрыты(сам):
        for ключ in ДЕКЛАРАЦИЯ:
            with сам.subTest(ключ=ключ):
                м = сам.включить(); м['имя_агентского_автора'][ключ] += '-иной'
                сам.сохранить(м); сам.отказ()

    def test_статус_приоритет_и_назначение_не_ослабляются(сам):
        for ключ, значение in (('статус', 'история'), ('приоритет', 'P2-тема'), ('назначение', {'путь': 'AGENTS.md', 'якорь': ПРАВИЛО})):
            with сам.subTest(ключ=ключ):
                м = сам.включить(); next(п for п in м['правила'] if п['идентификатор'] == ПРАВИЛО)[ключ] = значение
                сам.сохранить(м); сам.отказ()

    def test_неизвестные_поля_и_symlink_не_допускаются(сам):
        м = сам.включить(); м['имя_агентского_автора']['специализация'] = 'Разработчик'
        сам.сохранить(м); сам.отказ()
        м['имя_агентского_автора'] = copy.deepcopy(ДЕКЛАРАЦИЯ); сам.сохранить(м)
        файл = сам.корень / ДЕКЛАРАЦИЯ['автор']; данные = файл.read_bytes(); файл.unlink()
        цель = сам.корень / 'чужой.py'; цель.write_bytes(данные); файл.symlink_to(цель)
        сам.отказ()

    def test_скрытая_норма_отказана_без_профиля_состояния(сам):
        for начало, конец in (('<script>', '</script>'), ('<style>', '</style>'), ('<template>', '</template>'), ('<pre>', '</pre>'), ('<!-- скрытая область', '-->'), ('Примечание <div hidden>', 'Продолжение </div>'), ('Примечание ``<div hidden>``` x `', 'Продолжение ``</div>``` x `'), ('Примечание \\`<div hidden>\\`', 'Продолжение \\`</div>\\`'), ('Примечание <?скрыто', 'Продолжение ?>')):
            with сам.subTest(оболочка=начало):
                м = сам.включить(); файл = сам.корень / ТЕМА; текст = файл.read_text()
                автор = текст[текст.index('<!-- FUM-ПРАВИЛО: '+ПРАВИЛО+' -->'):]
                # Следующий действующий якорь остаётся зарегистрированным,
                # закрытие HTML идёт после него, вне точного тела 000063.
                файл.write_text('# сессия\n\n'+начало+'\n'+автор+'\n<!-- FUM-ПРАВИЛО: FUM-ПРАВИЛО-сессия -->\n'+конец+'\n- Правило темы сессия.\n')
                сам.сохранить(м); сам.отказ()

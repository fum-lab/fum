#!/usr/bin/env python3

import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


import os

def путь_проверяемой_реализации(путь: Path) -> Path:
    выбранный = os.environ.get("FUM_CHECKED_CODE_ROOT")
    if выбранный is None:
        return путь
    if not выбранный or not Path(выбранный).is_absolute():
        raise ValueError("корень проверяемой реализации должен быть явным абсолютным путём")
    return Path(выбранный) / путь.relative_to(Path(__file__).resolve().parents[3])


КОРЕНЬ_ИНСТРУМЕНТА = Path(__file__).resolve().parents[1]
СЦЕНАРИЙ = путь_проверяемой_реализации(КОРЕНЬ_ИНСТРУМЕНТА / "scripts" / "проверить-декомпозицию-правил.py")


def хэш_текста(текст: str) -> str:
    return "sha256:" + hashlib.sha256(текст.encode("utf-8")).hexdigest()


class ПроверкаДекомпозицииПравил(unittest.TestCase):
    def подготовить_стенд(это) -> None:
        временный_путь = это.enterContext(tempfile.TemporaryDirectory())
        это.корень = Path(временный_путь)
        это.создать_корректный_стенд()

    def записать(это, путь: str, текст: str) -> None:
        цель = это.корень / путь
        цель.parent.mkdir(parents=True, exist_ok=True)
        цель.write_text(текст, encoding="utf-8")

    def тематический_текст(это, идентификатор: str) -> str:
        return (
            f"# {идентификатор}\n\n"
            f"<!-- FUM-ПРАВИЛО: FUM-ПРАВИЛО-{идентификатор} -->\n"
            f"- Правило темы {идентификатор}.\n"
        )

    def создать_корректный_стенд(это) -> None:
        темы = [
            ("память", "Правила/агентов/память-и-документация.md"),
            ("язык", "Правила/агентов/язык-и-код.md"),
            ("сессия", "Правила/агентов/Git-и-рабочая-сессия.md"),
            ("навыки", "Правила/агентов/локальные-навыки-и-инструменты.md"),
            ("проверки", "Правила/агентов/проверки-коммит-и-публикация.md"),
            ("история", "Правила/агентов/исторический-конвейер.md"),
        ]
        маршруты = [
            ("только-чтение", []),
            ("изменение", [темы[2][1], темы[4][1]]),
            ("документация", [темы[0][1]]),
            ("код", [темы[1][1]]),
            ("инструменты", [темы[3][1]]),
            ("публикация", [темы[2][1], темы[4][1]]),
            ("правила", [путь for _, путь in темы]),
        ]
        строки_маршрутов = "\n".join(
            "<!-- FUM-МАРШРУТ: "
            + идентификатор
            + " => "
            + ";".join(пути)
            + " -->"
            for идентификатор, пути in маршруты
        )
        корневой_текст = (
            "# Правила\n\n"
            "<!-- FUM-WRITING-MODE: manual-sequential-v2 -->\n"
            "При нескольких триггерах читается объединение всех маршрутов; "
            "неоднозначность разрешается безопасным объединением.\n\n"
            + строки_маршрутов
            + "\n\n"
            "<!-- FUM-ПРАВИЛО: FUM-ПРАВИЛО-ЯДРО -->\n"
            "- Всегда критическое правило.\n"
        )
        это.записать("AGENTS.md", корневой_текст)

        описания_тем = []
        правила = [
            {
                "идентификатор": "FUM-ПРАВИЛО-ЯДРО",
                "статус": "действует",
                "приоритет": "P0-ядро",
                "области": ["всегда"],
                "триггеры": ["всегда"],
                "семантический_ключ": "ядро",
                "назначение": {"путь": "AGENTS.md", "якорь": "FUM-ПРАВИЛО-ЯДРО"},
                "источники": ["FUM-ИСТОЧНИК-ЯДРО"],
            }
        ]
        исходные_единицы = [
            {
                "идентификатор": "FUM-ИСТОЧНИК-ЯДРО",
                "начало_байта": 0,
                "конец_байта": 1,
                "sha256": хэш_текста("я"),
                "класс": "правило",
            }
        ]
        for номер, (идентификатор, путь) in enumerate(темы, start=1):
            текст = это.тематический_текст(идентификатор)
            это.записать(путь, текст)
            описания_тем.append(
                {
                    "идентификатор": идентификатор,
                    "путь": путь,
                    "полномочия": идентификатор != "история",
                    "sha256_содержания": хэш_текста(текст),
                }
            )
            идентификатор_правила = f"FUM-ПРАВИЛО-{идентификатор}"
            идентификатор_источника = f"FUM-ИСТОЧНИК-{номер:03d}"
            правила.append(
                {
                    "идентификатор": идентификатор_правила,
                    "статус": "история" if идентификатор == "история" else "действует",
                    "приоритет": "PH-без-полномочий" if идентификатор == "история" else "P2-тема",
                    "области": [идентификатор],
                    "триггеры": ["правила" if идентификатор == "история" else идентификатор],
                    "семантический_ключ": идентификатор,
                    "назначение": {"путь": путь, "якорь": идентификатор_правила},
                    "источники": [идентификатор_источника],
                }
            )
            исходные_единицы.append(
                {
                    "идентификатор": идентификатор_источника,
                    "начало_байта": номер,
                    "конец_байта": номер + 1,
                    "sha256": хэш_текста(идентификатор),
                    "класс": "правило",
                }
            )

        фикстуры = [
            {"идентификатор": "простой-вопрос", "триггеры": ["только-чтение"], "ожидаемые_пути": []},
            {
                "идентификатор": "правка-документации",
                "триггеры": ["изменение", "документация"],
                "ожидаемые_пути": [темы[0][1], темы[2][1], темы[4][1]],
            },
            {
                "идентификатор": "правка-кода",
                "триггеры": ["изменение", "код", "инструменты"],
                "ожидаемые_пути": [темы[1][1], темы[2][1], темы[3][1], темы[4][1]],
            },
            {
                "идентификатор": "публикация",
                "триггеры": ["публикация"],
                "ожидаемые_пути": [темы[2][1], темы[4][1]],
            },
            {
                "идентификатор": "изменение-правил",
                "триггеры": ["правила"],
                "ожидаемые_пути": [путь for _, путь in темы],
            },
            {
                "идентификатор": "смешанная-задача",
                "триггеры": ["изменение", "документация", "код", "инструменты"],
                "ожидаемые_пути": [путь for _, путь in темы if "исторический" not in путь],
            },
        ]
        манифест = {
            "схема": "fum.декомпозиция-правил-агентов.1",
            "исходный_снимок": {
                "commit": "0" * 40,
                "blob": "1" * 40,
                "sha256": "sha256:" + "2" * 64,
                "строк": 7,
                "unicode_символов": 7,
                "байтов": 7,
            },
            "ограничения_корня": {"строк": 120, "unicode_символов": 12000, "байтов": 24000},
            "темы": описания_тем,
            "маршруты": [
                {"идентификатор": идентификатор, "пути": пути}
                for идентификатор, пути in маршруты
            ],
            "фикстуры_маршрутизации": фикстуры,
            "исходные_единицы": исходные_единицы,
            "правила": правила,
        }
        это.записать(
            "Правила/агентов/инвентарь-правил.json",
            json.dumps(манифест, ensure_ascii=False, indent=2) + "\n",
        )

    def запустить(это, *аргументы: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [
                sys.executable,
                str(СЦЕНАРИЙ),
                "--корень-репозитория",
                str(это.корень),
                "--инвентарь",
                "Правила/агентов/инвентарь-правил.json",
                *аргументы,
            ],
            check=False,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )

    def загрузить_манифест(это) -> dict:
        путь = это.корень / "Правила/агентов/инвентарь-правил.json"
        return json.loads(путь.read_text(encoding="utf-8"))

    def сохранить_манифест(это, манифест: dict) -> None:
        это.записать(
            "Правила/агентов/инвентарь-правил.json",
            json.dumps(манифест, ensure_ascii=False, indent=2) + "\n",
        )

    def потребовать_отказ(это, фрагмент: str) -> None:
        результат = это.запустить("проверить")
        это.assertNotEqual(результат.returncode, 0, результат.stdout + результат.stderr)
        это.assertIn(фрагмент, результат.stderr)

    def test_принимает_полную_структуру_и_репрезентативные_маршруты(это) -> None:
        это.подготовить_стенд()
        результат = это.запустить("проверить")
        это.assertEqual(результат.returncode, 0, результат.stdout + результат.stderr)
        маршрут = это.запустить(
            "маршрут",
            "--триггер",
            "изменение",
            "--триггер",
            "документация",
            "--триггер",
            "код",
        )
        это.assertEqual(маршрут.returncode, 0, маршрут.stdout + маршрут.stderr)
        данные = json.loads(маршрут.stdout)
        это.assertEqual(
            данные["пути"],
            [
                "Правила/агентов/Git-и-рабочая-сессия.md",
                "Правила/агентов/память-и-документация.md",
                "Правила/агентов/проверки-коммит-и-публикация.md",
                "Правила/агентов/язык-и-код.md",
            ],
        )

    def test_отклоняет_незарегистрированное_правило(это) -> None:
        это.подготовить_стенд()
        путь = это.корень / "AGENTS.md"
        путь.write_text(путь.read_text(encoding="utf-8") +
                       "\n<!-- FUM-ПРАВИЛО: FUM-ПРАВИЛО-БЕЗ-ИНВЕНТАРЯ -->\n", encoding="utf-8")
        это.потребовать_отказ("не зарегистрирован")

    def test_отклоняет_активное_правило_в_исторической_теме(это) -> None:
        это.подготовить_стенд()
        манифест = это.загрузить_манифест()
        манифест["правила"][-1]["статус"] = "действует"
        это.сохранить_манифест(манифест)
        это.потребовать_отказ("без полномочий")

    def test_изоляция_сохраняет_запрет_автоконвейера(это) -> None:
        это.подготовить_стенд()
        путь = это.корень / "AGENTS.md"
        текст = путь.read_text(encoding="utf-8")
        политика = "\n<!-- FUM-WORKTREE-POLICY: isolated-per-task-v1 -->\n"
        путь.write_text(текст + политика, encoding="utf-8")
        это.потребовать_отказ("автоконвейера")
        путь.write_text(текст.replace("manual-sequential-v2", "manual-sequential-v1") + политика, encoding="utf-8")
        результат = это.запустить("проверить")
        это.assertEqual(результат.returncode, 0, результат.stderr)

    def test_отклоняет_отсутствующую_тему(это) -> None:
        это.подготовить_стенд()
        (это.корень / "Правила/агентов/язык-и-код.md").unlink()
        это.потребовать_отказ("не найден")

    def test_отклоняет_отключённую_границу_продолжения(это) -> None:
        это.подготовить_стенд()
        манифест = это.загрузить_манифест()
        манифест["продолжение_задачи"] = {"маркер": "explicit-worklist-v1", "сценарий": "проверить-продолжение.py"}
        это.сохранить_манифест(манифест)
        это.потребовать_отказ("продолжени")

    def включить_профиль_продолжения(это, имя="JSONL"):
        это.подготовить_стенд()
        путь_фикстуры = КОРЕНЬ_ИНСТРУМЕНТА / "tests/фикстуры/профили-продолжения.json"
        профиль = json.loads(путь_фикстуры.read_text(encoding="utf-8"))[имя]
        манифест = это.загрузить_манифест()
        граница = профиль["продолжение_задачи"]
        манифест["продолжение_задачи"] = граница
        пути = [граница["сценарий"]]
        if "остаток_сообщений" in граница:
            пути.append(граница["остаток_сообщений"]["сценарий"])
        for путь in пути:
            это.записать(путь, "# Открытая фикстура\n")
        путь = это.корень / "AGENTS.md"
        текст = путь.read_text() + "\n<!-- FUM-SESSION-CONTINUATION: explicit-worklist-v1 -->\n"
        for номер, норма in профиль["правила"].items():
            идентификатор = "FUM-ПРАВИЛО-" + номер
            текст += "\n<!-- FUM-ПРАВИЛО: " + идентификатор + " -->\n" + норма + "\n"
            манифест["правила"].append({**манифест["правила"][0],
                "идентификатор": идентификатор, "семантический_ключ": номер,
                "назначение": {"путь": "AGENTS.md", "якорь": идентификатор},
                "источники": [], "новое_основание": "AGENTS.md"})
        путь.write_text(текст)
        это.сохранить_манифест(манифест)
        return манифест

    def включить_границу_сообщений(это):
        return это.включить_профиль_продолжения("JSONL")

    def включить_дочернюю_передачу(это):
        манифест = это.включить_границу_сообщений()
        основание = 'FUM-ПРАВИЛО-000061'
        новое = 'FUM-ПРАВИЛО-НОВОЕ-000019'
        root = это.корень / 'AGENTS.md'
        root.write_text(root.read_text() + '\n<!-- FUM-ПРАВИЛО: ' + основание + ' -->\n'
            '- Конечная `дочерняя-передача` по `НОВОЕ-000019`; исключение только ребёнку.\n')
        манифест['правила'].append({**манифест['правила'][0], 'идентификатор': основание,
            'семантический_ключ': 'конечная-передача-основание',
            'назначение': {'путь': 'AGENTS.md', 'якорь': основание}, 'источники': [], 'новое_основание': 'AGENTS.md'})
        тема = 'Правила/агентов/проверки-коммит-и-публикация.md'

    @staticmethod
    def заменить_тело(текст, идентификатор, тело):
        import re
        образец = re.compile(r'(<!-- FUM-ПРАВИЛО: ' + re.escape(идентификатор)
            + r' -->\n)(.*?)(?=\n<!-- FUM-ПРАВИЛО:|\Z)', re.S)
        return образец.sub(lambda м: м[1] + тело + '\n', текст, count=1)


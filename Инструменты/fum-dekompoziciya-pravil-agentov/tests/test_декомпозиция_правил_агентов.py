        это.записать(тема, текст)
        for т in манифест['темы']:
            if т['путь'] == тема: т['sha256_содержания'] = хэш_текста(текст)
        манифест['правила'].append({'идентификатор': новое, 'статус': 'действует',
            'приоритет': 'P1-сессия', 'области': ['проверки'], 'триггеры': ['изменение'],
            'семантический_ключ': 'конечная-передача', 'назначение': {'путь': тема, 'якорь': новое},
            'источники': [], 'новое_основание': 'AGENTS.md'})
        конвейер = 'Инструменты/fum-konvejyer-proizvodnyikh-vetok/scripts/'
        манифест['дочерняя_передача'] = {'режим': 'дочерняя-передача', 'правило': новое,
            'корневое_основание': основание, 'получить_назначение': конвейер + 'получить-назначение.py',
            'проверить_передачу': конвейер + 'дочерний_коммит.py',
            'подготовить_окружение': конвейер + 'подготовить-окружение-слоя.py',
            'проверить_связность': конвейер + 'связность_слоя.py',
            'создать_коммит': 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/создание_коммита.py'}
        for ключ, путь in манифест['дочерняя_передача'].items():
            if ключ in {'получить_назначение', 'проверить_передачу', 'проверить_связность', 'создать_коммит', 'подготовить_окружение'}:
                это.записать(путь, '# Открытая фикстура\n')
        это.сохранить_манифест(манифест)
        return манифест


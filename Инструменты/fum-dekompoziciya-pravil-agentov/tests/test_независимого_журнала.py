    def test_новый_профиль_сохраняет_полное_исходное_покрытие(это):
        снимок = это.основа['исходный_снимок']
        исходные = гит(
            КОРЕНЬ_ОСНОВЫ, 'show', снимок['commit'] + ':AGENTS.md',
        )
        это.assertEqual(
            снимок['sha256'],
            'sha256:' + hashlib.sha256(исходные).hexdigest(),
        )
        случаи = (
            ('разрыв', 'исходный инвентарь покрыт неполно'),
            ('перекрытие', 'исходный инвентарь покрыт неполно'),
            ('повтор-диапазона', 'диапазон повторён'),
            ('обратный-диапазон', 'диапазон некорректен'),
            ('подмена-хэша', 'хэш диапазона не совпадает'),
        )
        for вид, сообщение in случаи:
            with это.subTest(вид=вид):
                корень, манифест = это.стенд(новый=True)
                единицы = манифест['исходные_единицы']
                номер = next(
                    н for н, е in enumerate(единицы)
                    if 0 < н < len(единицы) - 1
                    and е['конец_байта'] - е['начало_байта'] > 2
                )
                единица = единицы[номер]
                if вид == 'разрыв':
                    единица['начало_байта'] += 1
                elif вид == 'перекрытие':
                    единица['начало_байта'] -= 1
                elif вид == 'повтор-диапазона':
                    предыдущая = единицы[номер - 1]
                    for поле in ('начало_байта', 'конец_байта'):
                        единица[поле] = предыдущая[поле]
                elif вид == 'обратный-диапазон':
                    единица['конец_байта'] = единица['начало_байта']
                if вид == 'подмена-хэша':
                    единица['sha256'] = 'sha256:' + '0' * 64
                else:
                    # Отказ разрыва/перекрытия должен дойти до покрытия,
                    # а не остановиться на оставшемся старом SHA диапазона.
                    единица['sha256'] = 'sha256:' + hashlib.sha256(
                        исходные[
                            единица['начало_байта']:единица['конец_байта']
                        ],
                    ).hexdigest()
                это.assertEqual(265, len(единицы))
                это.сохранить(корень, манифест)
                процесс = это.потребовать_закрытый_отказ(корень)
                это.assertIn(сообщение, процесс.stderr)


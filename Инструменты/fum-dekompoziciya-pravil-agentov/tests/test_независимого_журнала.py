    def сохранить(это, корень, манифест):
        for тема in манифест['темы']:
            текст = (корень / тема['путь']).read_text()
            тема['sha256_содержания'] = 'sha256:' + hashlib.sha256(СВЕЖЕСТЬ.sub('', текст).encode()).hexdigest()
        (корень / ПУТЬ_ИНВЕНТАРЯ).write_text(json.dumps(манифест, ensure_ascii=False, indent=2) + '\n')

    def проверить(это, корень, успех):
        процесс = subprocess.run([sys.executable, '-B', str(СЦЕНАРИЙ),
            '--корень-репозитория', str(корень), 'проверить'], capture_output=True, text=True)
        это.assertEqual(процесс.returncode == 0, успех, процесс.stdout + процесс.stderr)
        return процесс


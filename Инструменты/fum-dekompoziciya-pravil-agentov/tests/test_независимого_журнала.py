def гит(корень, *аргументы):
    среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_NO_REPLACE_OBJECTS='1', GIT_OPTIONAL_LOCKS='0', GIT_NO_LAZY_FETCH='1',
        GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_SYSTEM=os.devnull)
    return subprocess.run(['git', '--no-replace-objects', '--no-optional-locks',
        '-c', 'core.hooksPath=' + os.devnull, '-C', str(корень), *аргументы],
        env=среда, check=True, capture_output=True).stdout


def байты_основы(путь):
    return гит(КОРЕНЬ_ОСНОВЫ, 'show', КОММИТ_ОСНОВЫ + ':' + путь)


def пути_сценариев(значение):
    if isinstance(значение, dict):
        for часть in значение.values(): yield from пути_сценариев(часть)
    elif isinstance(значение, list):
        for часть in значение: yield from пути_сценариев(часть)
    elif isinstance(значение, str) and значение.endswith('.py'): yield значение



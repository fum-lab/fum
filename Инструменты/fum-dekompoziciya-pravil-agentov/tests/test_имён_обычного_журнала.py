class ИменаОбычногоЖурнала(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        прежний.НезависимыйНормативныйПрофиль.setUpClass.__func__(класс)

    стенд = прежний.НезависимыйНормативныйПрофиль.стенд
    сохранить = прежний.НезависимыйНормативныйПрофиль.сохранить
    проверить = прежний.НезависимыйНормативныйПрофиль.проверить

    def заменить(это, корень, тела):
        файл = корень / ТЕМА
        текст = файл.read_text()
        for идентификатор, тело in тела.items():
            образец = r'(?m)(^<!-- FUM-ПРАВИЛО: ' + re.escape(идентификатор) + r' -->\n).*?(?=^<!-- FUM-ПРАВИЛО: |\Z)'
            текст, число = re.subn(образец, lambda с: с[1] + тело + '\n\n', текст, flags=re.S)
            это.assertEqual(1, число)
        файл.write_text(текст)

    def test_прежняя_пара_и_точная_новая_пара_проходят(это):
        корень, манифест = это.стенд(новый=True)
        это.проверить(корень, True)
        это.заменить(корень, ТЕЛА)
        это.сохранить(корень, манифест)
        это.проверить(корень, True)

    def test_смешанные_пары_и_расширения_отказывают_после_нового_SHA(это):
        for идентификатор in ТЕЛА:
            with это.subTest(смешанная=идентификатор):
                корень, манифест = это.стенд(новый=True)
                это.заменить(корень, {идентификатор: ТЕЛА[идентификатор]})
                это.сохранить(корень, манифест)
                это.проверить(корень, False)
            with это.subTest(расширение=идентификатор):
                корень, манифест = это.стенд(новый=True)
                это.заменить(корень, ТЕЛА | {идентификатор: ТЕЛА[идентификатор] + ' Любые другие каталоги также разрешены.'})
                это.сохранить(корень, манифест)
                это.проверить(корень, False)

    def test_подмена_назначения_или_удаление_одной_нормы_отказывает(это):
        for поле in ('приоритет', 'назначение', 'удаление'):
            with это.subTest(поле=поле):
                корень, манифест = это.стенд(новый=True)
                это.заменить(корень, ТЕЛА)
                запись = next(н for н in манифест['правила'] if н['идентификатор'] == 'FUM-ПРАВИЛО-000016')
                if поле == 'удаление':
                    манифест['правила'].remove(запись)
                else:
                    запись[поле] = 'подмена'
                это.сохранить(корень, манифест)
                это.проверить(корень, False)

    def test_точное_покрытие_инвентаря_сохраняет_каждое_поле(это):
        корень = Path(os.environ.get('FUM_CHECKED_CODE_ROOT', str(прежний.КОРЕНЬ_ОСНОВЫ)))
        исходный = json.loads((корень / прежний.ПУТЬ_ИНВЕНТАРЯ).read_bytes())
        прежний.проверить_точный_инвентарь_имён(это, исходный)
        for случай in ('пропуск', 'дубль', 'иной_ID', 'подмена_нормы', 'подмена_источника',
                       'сводка', 'SHA_темы', 'новое_поле'):
            with это.subTest(случай=случай):
                кандидат = copy.deepcopy(исходный)
                if случай == 'пропуск': кандидат['правила'].pop()
                elif случай == 'дубль': кандидат['правила'].append(copy.deepcopy(кандидат['правила'][0]))
                elif случай == 'иной_ID': кандидат['правила'][0]['идентификатор'] += '-подмена'
                elif случай == 'подмена_нормы': кандидат['правила'][0]['приоритет'] = 'P2-тема'
                elif случай == 'подмена_источника': кандидат['исходные_единицы'][0]['sha256'] = 'подмена'
                elif случай == 'сводка':
                    next(н for н in кандидат['правила'] if н['идентификатор'] in ТЕЛА)['краткое_содержание'] = 'Любые имена'
                elif случай == 'SHA_темы': кандидат['темы'][0]['sha256_содержания'] = 'sha256:' + '0' * 64
                else: кандидат['неизвестное_поле'] = True
                with это.assertRaises(AssertionError):
                    прежний.проверить_точный_инвентарь_имён(это, кандидат)


if __name__ == '__main__':
    unittest.main()

    def байты_патча(сам, путь: str = "Документация/пример.md") -> bytes:
        содержимое = "Проверяемый внешний вклад.\n".encode("utf-8")
        новый_идентификатор_объекта = идентификатор_объекта_данных(содержимое)
        return (
            f"diff --git a/{путь} b/{путь}\n"
            "new file mode 100644\n"
            f"index {'0' * 40}..{новый_идентификатор_объекта}\n"
            "--- /dev/null\n"
            f"+++ b/{путь}\n"
            "@@ -0,0 +1 @@\n"
            "+Проверяемый внешний вклад.\n"
        ).encode("utf-8")

    def байты_патча_изменения(сам, старый_идентификатор_объекта: str | None = None) -> bytes:
        до = b"base\n"
        после = b"changed\n"
        старый_идентификатор_объекта = идентификатор_объекта_данных(до) if старый_идентификатор_объекта is None else старый_идентификатор_объекта
        return (
            "diff --git a/README.md b/README.md\n"
            f"index {старый_идентификатор_объекта}..{идентификатор_объекта_данных(после)} 100644\n"
            "--- a/README.md\n"
            "+++ b/README.md\n"
            "@@ -1 +1 @@\n"
            "-base\n"
            "+changed\n"
        ).encode("utf-8")


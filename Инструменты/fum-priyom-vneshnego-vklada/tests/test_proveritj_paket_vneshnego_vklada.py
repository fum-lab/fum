def запустить(*аргументы: str, рабочий_каталог: Path, входные_байты: bytes | None = None) -> subprocess.CompletedProcess[bytes]:
    return системный_запуск(
        list(аргументы),
        cwd=рабочий_каталог,
        input=входные_байты,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )


def идентификатор_объекта_данных(содержимое: bytes) -> str:
    заголовок = f"blob {len(содержимое)}\0".encode("ascii")
    return hashlib.sha1(заголовок + содержимое).hexdigest()


def закодировать_переменный_размер(значение: int) -> bytes:
    результат = bytearray()
    while True:
        байт = значение & 0x7F
        значение >>= 7
        результат.append(байт | (0x80 if значение else 0))
        if not значение:
            return bytes(результат)


def закодировать_базу85_системы_версий(данные: bytes) -> bytes:
    строки: list[str] = []
    for начало in range(0, len(данные), 52):
        порция = данные[начало : начало + 52]
        длина = len(порция)
        префикс = chr(ord("A") + длина - 1) if длина <= 26 else chr(ord("a") + длина - 27)
        дополненная_порция = порция + b"\0" * ((-длина) % 4)
        знаки: list[str] = []
        for позиция in range(0, len(дополненная_порция), 4):
            значение = int.from_bytes(дополненная_порция[позиция : позиция + 4], "big")
            группа = [АЛФАВИТ_БАЗЫ85_СИСТЕМЫ_ВЕРСИЙ[0]] * 5
            for индекс in range(4, -1, -1):
                значение, цифра = divmod(значение, 85)
                группа[индекс] = АЛФАВИТ_БАЗЫ85_СИСТЕМЫ_ВЕРСИЙ[цифра]
            знаки.extend(группа)
        строки.append(префикс + "".join(знаки))
    return ("\n".join(строки) + "\n").encode("ascii")


def бинарный_фрагмент(вид: str, распакованные_данные: bytes) -> bytes:
    сжатые_данные = zlib.compress(распакованные_данные)
    return (
        f"{вид} {len(распакованные_данные)}\n".encode("ascii")
        + закодировать_базу85_системы_версий(сжатые_данные)
    )



    def бинарный_патч_добавления(сам, путь: str, содержимое: bytes) -> bytes:
        цель = сам.репозиторий / путь
        цель.parent.mkdir(parents=True, exist_ok=True)
        цель.write_bytes(содержимое)
        сам.assertEqual(запустить("git", "add", "-N", "--", путь, рабочий_каталог=сам.репозиторий).returncode, 0)
        патч = запустить(
            "git",
            "-c",
            "core.quotePath=false",
            "diff",
            "--binary",
            "--full-index",
            "--no-renames",
            "--no-color",
            "--src-prefix=a/",
            "--dst-prefix=b/",
            "--no-ext-diff",
            "--no-textconv",
            "--",
            путь,
            рабочий_каталог=сам.репозиторий,
        )
        сам.assertEqual(патч.returncode, 0, патч.stderr.decode())
        сам.assertEqual(запустить("git", "reset", "-q", "--", путь, рабочий_каталог=сам.репозиторий).returncode, 0)
        цель.unlink()
        return патч.stdout


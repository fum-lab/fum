    def test_отложенная_задача_связывается_по_точному_нативному_поручению(проверка):
        for подмена in (False, True):
            with проверка.subTest(подмена=подмена), открытый_вход() as (корень, источник, решение):
                исполнитель, результат, коммит, ветка = подготовленная_постановка(корень, источник, решение)
                with mock.patch.object(исполнение, "проверить_инструменты"):
                    исполнитель.закрепить_постановку(результат["событие"], коммит, ветка)
                    допуск = исполнитель.допустить_вызов(источник, ЗАДАЧА, решение)
                исполнитель.сохранить_ответ(допуск["событие"], допуск["попытка"], {"clientThreadId": "отложенный"})
                ребёнок = корень.parent / "ребёнок"
                задача = "00000000-0000-0000-0000-000000000202"
                исполнение.хранилище.гит(корень, "worktree", "add", "-b", "codex/ребёнок", str(ребёнок), коммит)
                нативный = корень.parent / "нативный.jsonl"
                поручение = "Иное поручение" if подмена else допуск["аргументы"]["prompt"]
                from xml.sax.saxutils import escape
                оболочка = "<codex_delegation>\n  <source_thread_id>" + ЗАДАЧА + "</source_thread_id>\n  <input>" + escape(поручение) + "</input>\n</codex_delegation>"
                нативный.write_bytes(строка({"type": "session_meta", "payload": {"id": задача, "cwd": str(ребёнок), "git": {"commit_hash": коммит}}})
                    + строка({"type": "turn_context", "payload": {"cwd": str(ребёнок), "model": "gpt-6-astra", "effort": "ultra"}})
                    + строка({"type": "response_item", "payload": {"type": "function_call_output", "name": "create_thread", "output": оболочка}}))
                исполнение.база.подтвердить_начало(ребёнок, задача, коммит, нативный)
                if подмена:
                    with проверка.assertRaises(исполнение.ОшибкаПриёма):
                        исполнитель.наблюдать(допуск["событие"], ребёнок, задача, нативный)
                else:
                    первый = исполнитель.наблюдать(допуск["событие"], ребёнок, задача, нативный)
                    второй = исполнитель.наблюдать(допуск["событие"], ребёнок, задача, нативный)
                    проверка.assertEqual(задача, первый["задача"])
                    проверка.assertEqual(первый, второй)
                    проверка.assertFalse(исполнитель.допустить_вызов(источник, ЗАДАЧА, решение)["разрешён_вызов"])


def измерить_исполнение(выход):
    import json
    import platform
    import statistics
    import time
    стадии = {имя: [] for имя in ("локальная подготовка", "закрепление коммита", "первый допуск", "повтор допуска")}
    for повтор in range(3):
        with открытый_вход() as (корень, источник, решение):
            запрос = журнал(корень)
            решение["действие"] = "обновить"
            исполнитель = исполнение.ИсполнительПриёма(корень, ЗАДАЧА)
            def измерить(имя, операция):
                начало = time.perf_counter_ns()
                результат = операция()
                стадии[имя].append(time.perf_counter_ns() - начало)
                return результат
            with mock.patch.object(исполнение, "проверить_планирование", return_value="{}\n"), mock.patch.object(исполнение, "проверить_инструменты"):
                местное = измерить("локальная подготовка", lambda: исполнитель.подготовить(источник, ЗАДАЧА, решение, запрос, []))
                исполнение.хранилище.гит(корень, "add", ".")
                исполнение.хранилище.гит(корень, "commit", "-qm", "Профиль постановки")
                коммит = исполнение.хранилище.гит(корень, "rev-parse", "HEAD").strip()
                ветка = исполнение.хранилище.гит(корень, "symbolic-ref", "HEAD").strip()
                измерить("закрепление коммита", lambda: исполнитель.закрепить_постановку(местное["событие"], коммит, ветка))
                первый = измерить("первый допуск", lambda: исполнитель.допустить_вызов(источник, ЗАДАЧА, решение))
                второй = измерить("повтор допуска", lambda: исполнитель.допустить_вызов(источник, ЗАДАЧА, решение))
                assert местное["готов"] and первый["разрешён_вызов"] and not второй["разрешён_вызов"] and первый["попытка"] == второй["попытка"]
    файлы = [Path(исполнение.__file__), Path(исполнение.вход.__file__), Path(исполнение.хранилище.__file__), Path(исполнение.база.__file__), Path(__file__)]
    данные = {"схема": "fum.профиль-исполнения-приёма.1", "python": platform.python_version(), "платформа": platform.system(),
              "код": {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in файлы},
              "стадии": {имя: {"наносекунды": замеры, "медиана_мс": statistics.median(замеры) / 1e6} for имя, замеры in стадии.items()},
              "граница": "Три отдельные открытые фикстуры с реальным Git и JSONL. Создание фикстуры и коммит исключены. Сборщик всего реестра и допуск кода своего checkout заменены подстановками. Native API не вызывался; стадии последовательны и не вложены."}
    Path(выход).write_text(json.dumps(данные, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({имя: значение["медиана_мс"] for имя, значение in данные["стадии"].items()}, ensure_ascii=False))



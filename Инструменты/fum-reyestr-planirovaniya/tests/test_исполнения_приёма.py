    def test_новый_процесс_продолжает_частично_установленный_план(проверка):
        with открытый_вход() as (корень, источник, решение):
            запрос = журнал(корень)
            решение["действие"] = "обновить"
            исполнитель = исполнение.ИсполнительПриёма(корень, ЗАДАЧА)
            исходная = исполнение.хранилище.установить
            прервано = False
            def оборвать(путь, данные):
                nonlocal прервано
                исходная(путь, данные)
                if путь == корень / запрос and not прервано:
                    прервано = True
                    raise OSError("Прерывание после первой цели")
            with mock.patch.object(исполнение, "проверить_планирование", return_value="{}\n"):
                with mock.patch.object(исполнение.хранилище, "установить", side_effect=оборвать):
                    with проверка.assertRaises(OSError):
                        исполнитель.подготовить(источник, ЗАДАЧА, решение, запрос, [])
                результат = исполнение.ИсполнительПриёма(корень, ЗАДАЧА).подготовить(источник, ЗАДАЧА, решение, запрос, [])
            проверка.assertTrue(результат["готов"])
            проверка.assertEqual(1, (корень / запрос).read_text().count(решение["экземпляр"]))


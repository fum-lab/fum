    папка.mkdir(parents=True)
    запрос = папка / "запрос.md"
    запрос.write_text("# Запрос\n\n## Текст запроса\n\n```text\nРанее.\n```\n\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: " + ЗАДАЧА + "\n")

            сокращённый["назначения"][0]["исходная_постановка"].update(событие=None, сохранённая_запись_sha256=None)
            with проверка.assertRaises(хранение.ОшибкаПриёма):
                исполнитель.предпросмотр(сокращённый)
            байты_события = хранение.байты(старая)
            журнал_до = {имя: (корень / имя).read_bytes() for имя in старая["постановка"]["файлы"] if имя.startswith("Журнал/")}
            план, коммит = привязать_пакет(исполнитель, корень, пакет)

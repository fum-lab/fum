    def test_после_неизвестного_исхода_новый_коммит_не_создаёт_повтор(проверка):
        with пакет_фикстуры(2) as (корень, пакет):
            исполнитель = проверка.исполнитель(корень)
            план = исполнитель.предпросмотр(пакет)
            исполнитель.подготовить(пакет, план["sha256"])
            хранение.гит(корень, "add", ".")
            хранение.гит(корень, "commit", "-qm", "Запуск")
            коммит = хранение.гит(корень, "rev-parse", "HEAD").strip()
            ветка = хранение.гит(корень, "symbolic-ref", "HEAD").strip()
            with mock.patch.object(прежний, "проверить_инструменты"), mock.patch.object(прежний, "проверить_планирование", return_value="{}"):
                исполнитель.закрепить(план["пакет"], коммит, ветка)
                первый = исполнитель.допустить(пакет, "FUM-STEP-0001")
                проверка.assertTrue(первый["разрешён_вызов"])
                второй = проверка.исполнитель(корень).допустить(пакет, "FUM-STEP-0001")
                проверка.assertFalse(второй["разрешён_вызов"])
                проверка.assertEqual(первый["попытка"], второй["попытка"])
                процесс = команда_процесса(корень, пакет, "допустить-назначение", "--направление", "FUM-STEP-0001")

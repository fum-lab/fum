"""Защита выбранного профиля адресата до внешнего вызова."""
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import профиль_продолжения as профиль

АДРЕСАТ = "00000000-0000-0000-0000-000000000001"


class ПроверкаПрофиляПродолжения(unittest.TestCase):
    def setUp(сам):
        сам.выбор = {"исполнитель": АДРЕСАТ, "профиль": {"model": "gpt-6.1-sol", "thinking": "ultra"}}
        сам.вызов = {"threadId": АДРЕСАТ, "prompt": "Продолжить сохранённый этап"}

    def test_пропуск_параметров_заполняется_выбором_адресата(сам):
        результат = профиль.подготовить(сам.выбор, сам.вызов)
        сам.assertEqual({**сам.вызов, **сам.выбор["профиль"]}, результат)
        сам.assertEqual({"threadId", "prompt"}, set(сам.вызов))

    def test_астра_вместо_выбранной_sol_отвергается(сам):
        with сам.assertRaises(ValueError):
            профиль.подготовить(сам.выбор, {**сам.вызов, "model": "gpt-6-astra", "thinking": "ultra"})

    def test_ошибочное_усилие_отвергается(сам):
        with сам.assertRaises(ValueError):
            профиль.подготовить(сам.выбор, {**сам.вызов, "thinking": "low"})

    def test_чужой_адресат_отвергается(сам):
        with сам.assertRaises(ValueError):
            профиль.подготовить(сам.выбор, {**сам.вызов, "threadId": "00000000-0000-0000-0000-000000000002"})

    def test_явный_совпадающий_профиль_и_host_сохраняются(сам):
        вызов = {**сам.вызов, **сам.выбор["профиль"], "hostId": "local"}
        сам.assertEqual(вызов, профиль.подготовить(сам.выбор, вызов))

    def test_нет_привязки_к_одной_модели(сам):
        выбор = {"исполнитель": АДРЕСАТ, "профиль": {"model": "provider/future-model.v7", "thinking": "future-effort"}}
        сам.assertEqual(выбор["профиль"]["model"], профиль.подготовить(выбор, сам.вызов)["model"])

    def test_неполный_выбор_не_получает_неявных_настроек(сам):
        for выбор in ({}, {"исполнитель": АДРЕСАТ}, {**сам.выбор, "профиль": {"model": "gpt-6.1-sol"}}):
            with сам.subTest(выбор=выбор), сам.assertRaises(ValueError):
                профиль.подготовить(выбор, сам.вызов)

    def test_неизвестные_аргументы_и_пустой_текст_отвергаются(сам):
        for вызов in ({**сам.вызов, "prompt": " "}, {**сам.вызов, "root_model": "gpt-6-astra"}):
            with сам.subTest(вызов=вызов), сам.assertRaises(ValueError):
                профиль.подготовить(сам.выбор, вызов)


if __name__ == "__main__":
    unittest.main()

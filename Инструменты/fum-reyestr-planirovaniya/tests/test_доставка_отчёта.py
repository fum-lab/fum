    def test_настоящий_процесс_и_интерфейс_после_аварии(сам):
        план = сам.ф.папка / "план.json"
        план.write_bytes(байты(сам.ф.план()))
        исходники = Path(__file__).resolve().parents[1] / "scripts"
        общие = ["--план", str(план), "--корень", str(сам.ф.цель), "--задача", ЗАДАЧА,
                 "--владельцы", str(сам.ф.реестр), "--каталог", str(сам.ф.папка / "состояние")]
        среда = dict(os.environ, CODEX_THREAD_ID=ЗАДАЧА)
        сценарий = сам.ф.папка / "авария.py"
        сценарий.write_text("import os,sys,json\nfrom pathlib import Path\nsys.path.insert(0,sys.argv[1])\n"
            "from обратная_доставка import Доставка\n"
            "д=Доставка(json.loads(Path(sys.argv[2]).read_bytes()),sys.argv[3],sys.argv[4],sys.argv[5],sys.argv[6])\n"
            "д.применить()\nд._после_проверки=lambda:os._exit(23)\n"
            "д.проверить([sys.executable,'-B','-c',\"print('готово')\"],запрос=sys.argv[7],корневая_задача=sys.argv[8])\n")
        результат = subprocess.run([sys.executable, "-B", str(сценарий), str(исходники), str(план), str(сам.ф.цель),
                                    ЗАДАЧА, str(сам.ф.реестр), str(сам.ф.папка / "состояние"), сам.запрос, КООРДИНАТОР],
                                   cwd=сам.ф.цель, env=среда, capture_output=True)
        сам.assertEqual(результат.returncode, 23, результат.stderr)
        for действие in ("состояние", "индекс", "коммит"):
            if действие == "индекс":
                гит(сам.ф.цель, "add", ".")
            if действие == "коммит":
                гит(сам.ф.цель, "commit", "-m", "Проверенное слияние")
            результат = subprocess.run([sys.executable, "-B", str(исходники / "обратная-доставка.py"), действие, *общие],
                                       cwd=сам.ф.цель, env=среда, capture_output=True)
            сам.assertEqual(результат.returncode, 0, результат.stderr)
            сам.assertEqual(json.loads(результат.stdout)["стадия"], {"состояние": "ожидается индекс", "индекс": "проверено", "коммит": "закоммичено"}[действие])


"""Реальная отчётная обёртка на открытом минимальном Git-репозитории."""
import json
import os
from pathlib import Path
import sys
import tempfile
import subprocess
import unittest
from unittest.mock import patch

from test_обратная_доставка import Фикстура, гит, КООРДИНАТОР, ЗАДАЧА
import test_обратная_доставка as базовые
from приём_направления import ОшибкаПриёма, байты
import доставка_отчёта
import обратная_доставка


class ПроверкиОтчётнойДоставки(unittest.TestCase):
    def __init__(сам, *аргументы, **именованные):
        super().__init__(*аргументы, **именованные)
        сам.временное = tempfile.TemporaryDirectory(prefix="fum-отчёт-доставки-")
        сам.addCleanup(сам.временное.cleanup)
        сам.ф = Фикстура(сам.временное.name)
        сам.запрос = "Журнал/2026-09-15_12-00-00_MSK_проверить-доставку/запрос.md"
        сам.папка = сам.ф.цель / Path(сам.запрос).parent
        сам.папка.mkdir(parents=True)
        (сам.папка / "запрос.md").write_text("# Исходный запрос\n\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: " + КООРДИНАТОР + "\n")
        сам.отчёт = сам.папка / "отчёт.md"
        сам.отчёт.write_text("# Отчёт\n\nСохранить введение.\n\n<!-- FUM-CHECK-RUNS:BEGIN состояние=открыт; каталог=материалы/запуски-проверок -->\nПока пусто.\n<!-- FUM-CHECK-RUNS:END -->\n\nСохранить хвост.\n")
        сам.ф.коммит(сам.ф.цель)

    def проверить(сам, доставка, код="print('готово')"):
        return доставка.проверить([sys.executable, "-B", "-c", код], запрос=сам.запрос,
                                 корневая_задача=КООРДИНАТОР)

    def test_настоящая_обёртка_и_явный_индекс(сам):
        with сам.ф.владелец() as доставка:
            исходная = доставка.применить()["дерево"]
            with доставка.хранилище.замок() as хранилище:
                старая = хранилище.прочитать()
                старая["схема"] = "fum.квитанция-обратной-доставки.1"
                старая.pop("отчёт")
                хранилище.сохранить(старая)
            итог = сам.проверить(доставка)
            сам.assertEqual(итог["схема"], "fum.квитанция-обратной-доставки.2")
            сам.assertEqual(итог["стадия"], "ожидается индекс")
            сам.assertEqual(гит(сам.ф.цель, "write-tree"), исходная)
            with сам.assertRaises(ОшибкаПриёма):
                доставка.подтвердить_индекс()
            гит(сам.ф.цель, "add", "--", str(сам.папка.relative_to(сам.ф.цель)))
            квитанция = доставка.подтвердить_индекс()
            сам.assertEqual(квитанция["стадия"], "проверено")
            сам.assertEqual(квитанция["отчёт"]["дерево_слияния"], исходная)
            сам.assertNotEqual(квитанция["дерево"], исходная)
            сам.assertEqual(len(квитанция["отчёт"]["разница"]), 2)
            гит(сам.ф.цель, "commit", "-m", "Доставка с отчётом")
            сам.assertEqual(доставка.подтвердить_коммит()["стадия"], "закоммичено")
            сам.assertEqual(доставка.подтвердить_получение("Проверка владельца")["получатель"], "подтверждено")

    def test_изменение_вне_маркера_не_перезаписывается(сам):
        with сам.ф.владелец() as доставка:
            доставка.применить()
            with сам.assertRaises(ОшибкаПриёма):
                сам.проверить(доставка, "from pathlib import Path; p=Path(" + repr(str(сам.отчёт.relative_to(сам.ф.цель))) + "); p.write_text(p.read_text().replace('Сохранить хвост.', 'Подмена хвоста.'))")
            сам.assertIn("Подмена хвоста.", сам.отчёт.read_text())

    def test_посторонний_файл_не_принимается(сам):
        with сам.ф.владелец() as доставка:
            доставка.применить()
            with сам.assertRaises(ОшибкаПриёма):
                сам.проверить(доставка, "from pathlib import Path; Path('постороннее.txt').write_text('лишнее')")

    def test_чужая_сессия_отказывает_до_проверки(сам):
        with сам.ф.владелец() as доставка:
            доставка.применить()
            with сам.assertRaises(ОшибкаПриёма):
                доставка.проверить([sys.executable, "-c", "raise Exception('не запускать')"], запрос=сам.запрос,
                                  корневая_задача="00000000-0000-0000-0000-000000000099")

    def test_ошибка_проверки_сохраняет_терминал_и_запрещает_коммит(сам):
        with сам.ф.владелец() as доставка:
            доставка.применить()
            итог = сам.проверить(доставка, "raise SystemExit(7)")
            сам.assertEqual(итог["стадия"], "проверка не пройдена")
            сам.assertIn("неуспешно", сам.отчёт.read_text())
            with сам.assertRaises(ОшибкаПриёма):
                доставка.подтвердить_индекс()

    def test_потеря_ответа_не_повторяет_проверку(сам):
        план = сам.ф.план()
        with сам.ф.владелец(план) as доставка:
            доставка.применить()
            with patch.object(доставка, "_после_проверки", side_effect=RuntimeError("сбой")), сам.assertRaises(RuntimeError):
                сам.проверить(доставка)
        with сам.ф.владелец(план) as доставка:
            итог = доставка.состояние()
            сам.assertEqual(итог["стадия"], "ожидается индекс")
            сам.assertEqual(len(list((сам.папка / "материалы/запуски-проверок").glob("*.json"))), 1)
            сам.assertEqual(доставка.состояние(), итог)

    def test_подмена_разницы_после_проверки_отказывает(сам):
        with сам.ф.владелец() as доставка:
            доставка.применить()
            сам.проверить(доставка)
            путь = next((сам.папка / "материалы/запуски-проверок").glob("*.json"))
            запись = json.loads(путь.read_bytes()); запись["исполнитель"] = "Подмена"
            путь.write_text(json.dumps(запись, ensure_ascii=False))
            гит(сам.ф.цель, "add", ".")
            with сам.assertRaises(ОшибкаПриёма):
                доставка.подтвердить_индекс()

    def test_потеря_ответа_до_сохранения_метаданных(сам):
        план = сам.ф.план()
        исходная = обратная_доставка.захватить_с_хэшем
        def сбой(*аргументы, **именованные):
            исходная(*аргументы, **именованные)
            raise RuntimeError("Ответ захвата потерян")
        with сам.ф.владелец(план) as доставка:
            доставка.применить()
            with patch.object(обратная_доставка, "захватить_с_хэшем", side_effect=сбой), сам.assertRaises(RuntimeError):
                сам.проверить(доставка)
        with сам.ф.владелец(план) as доставка:
            сам.assertEqual(доставка.состояние()["стадия"], "ожидается индекс")

    def test_потеря_ответа_после_предпросмотра(сам):
        план = сам.ф.план()

    def test_ввод_до_либо_во_время_сверки_префикса_требует_нового_решения(проверка):
        for до_сверки in (True, False):
            with проверка.subTest(до_сверки=до_сверки), открытый_вход() as (корень, источник, решение):
                исходная = вход.обработка.сверить_границы
                добавлено = False
                def добавить():
                    nonlocal добавлено
                    if not добавлено:
                        with источник.open("ab") as поток:
                            поток.write(строка(сообщение("Отменяю создание задачи.\n", 3)))
                        добавлено = True
                def сверить(*аргументы, **параметры):
                    адресная = аргументы[1] == [решение["контекст"]]
                    if адресная and до_сверки:
                        добавить()
                    результат = исходная(*аргументы, **параметры)
                    if адресная and not до_сверки:
                        добавить()
                    return результат
                with mock.patch.object(вход.обработка, "сверить_границы", side_effect=сверить):
                    with проверка.assertRaises(ОшибкаПриёма):
                        проверить_решение(корень, источник, ЗАДАЧА, решение)
                проверка.assertTrue(добавлено)


import вход_направления as вход

ЗАДАЧА = "00000000-0000-0000-0000-000000000201"


def строка(значение):
    return (json.dumps(значение, ensure_ascii=False) + "\n").encode()


def сообщение(текст, номер, вид="user.text"):
    return {"type": "response_item", "payload": {
        "type": "message", "role": "user", "id": str(номер),
        "content": [{"type": "input_text", "text": текст}],
        "internal_chat_message_metadata_passthrough": {"content_item_kinds": [вид]}}}


@contextmanager
def открытый_вход():
    with tempfile.TemporaryDirectory() as имя:
        корень = Path(имя).resolve() / "репозиторий"
        корень.mkdir()
        for аргументы in (("init", "-q", "-b", "codex/приём"), ("config", "user.name", "Открытая фикстура"), ("config", "user.email", "fixture@example.invalid")):
            subprocess.run(["git", *аргументы], cwd=корень, check=True, capture_output=True)
        (корень / "README.md").write_text("Открытый вход\n")
        subprocess.run(["git", "add", "."], cwd=корень, check=True)
        subprocess.run(["git", "commit", "-qm", "Основа"], cwd=корень, check=True)
        источник = корень.parent / "диалог.jsonl"
        источник.write_bytes(строка({"type": "session_meta", "payload": {"id": ЗАДАЧА}}) + строка(сообщение("Создавай отдельные задачи направлений.\n", 1)) + строка(сообщение("Направление — математика.\n", 2)))
        снимок = прочитать_вход(корень, источник, ЗАДАЧА)
        решение = {"схема": "fum.решение-приёма.1", "экземпляр": снимок["сообщения"][-1]["экземпляр"], "контекст": снимок["контекст"], "история_sha256": снимок["история_sha256"], "актуальность": "актуально", "поздние": [], "основание": "Разрешение отдельной задачи дано первым сообщением; предметная реализация не поручена.", "ответ": "Принято планирование математики.", "действие": "новое", "объём": "планирование", "задача": {"режим": "создать", "разрешение": [снимок["сообщения"][0]["экземпляр"]], "поручение": "Составить проверяемый план математики.", "projectId": "открытый-проект", "title": "Математика"}}
        yield корень, источник, решение


class ПроверкаВхода(unittest.TestCase):
    def test_внешний_допуск_без_местной_стадии_запрещён(проверка):
        with открытый_вход() as (корень, источник, решение):
            исполнитель = вход.ИсполнительПриёма(корень, ЗАДАЧА)
            with проверка.assertRaises(ОшибкаПриёма):
                исполнитель.допустить_вызов(источник, ЗАДАЧА, решение)

    def test_повтор_высокого_уровня_не_создаёт_вторую_попытку(проверка):
        with открытый_вход() as (корень, источник, решение):
            папка = корень / "Журнал/2026-09-11_01-00-00_MSK_принять-направление"
            папка.mkdir(parents=True)
            запрос = (папка / "запрос.md").relative_to(корень).as_posix()
            (корень / запрос).write_text("# Запрос\n\n## Текст запроса\n\n```text\nРанее.\n```\n\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: " + ЗАДАЧА + "\n")
            (папка / "отчёт.md").write_text("# Отчёт\n\nНачато.\n\n## Профиль времени выполнения\n\nОткрытый профиль.\n")
            решение["действие"] = "обновить"
            исполнитель = вход.ИсполнительПриёма(корень, ЗАДАЧА)
            with mock.patch.object(вход, "проверить_планирование", return_value=None), mock.patch.object(вход, "проверить_код_в_коммите", return_value=None):
                местное = исполнитель.подготовить(источник, ЗАДАЧА, решение, запрос, [])
                первый = исполнитель.допустить_вызов(источник, ЗАДАЧА, решение)
                проверка.assertTrue(первый["разрешён_вызов"])
                второй = исполнитель.допустить_вызов(источник, ЗАДАЧА, решение)
                проверка.assertFalse(второй["разрешён_вызов"])
                проверка.assertEqual(первый["попытка"], второй["попытка"])
                проверка.assertEqual("ultra", первый["аргументы"]["thinking"])
                проверка.assertEqual("gpt-6-astra", первый["аргументы"]["model"])
                проверка.assertEqual(местное["событие"], первый["событие"])

    def test_карточка_получает_номер_и_индекс_автоматически(проверка):
        with открытый_вход() as (корень, источник, решение):
            каталог = корень / "Планирование/карточки-шагов"
            каталог.mkdir(parents=True)
            (каталог / "README.md").write_text("# Карточки\n\n| Идентификатор | Статус | Карточка |\n| --- | --- | --- |\n")
            описание = [{"тип": "шаг", "операция": "создать", "имя": "спланировать-математику", "заголовок": "Спланировать математику", "содержимое": "## Задача\n\nПлан математики.\n\n## Почему сейчас\n\nПрямой запрос.\n\n## Критерии завершения\n\n- Проверяемый план.\n"}]
            файлы = вход.подготовить_карточки(корень, описание, {"FUM-STEP": "FUM-STEP-0202"}, "Журнал/2026-09-11_01-00-00_MSK_принять-направление/запрос.md")
            имя = "Планирование/карточки-шагов/🟡-FUM-STEP-0202-спланировать-математику.md"
            проверка.assertIn('card_id = "FUM-STEP-0202"', файлы[имя])
            проверка.assertIn("🟡 Актуально", файлы["Планирование/карточки-шагов/README.md"])
            проверка.assertFalse((корень / имя).exists())
            (корень / имя).write_text(файлы[имя])
            with проверка.assertRaises(ОшибкаПриёма):
                вход.подготовить_карточки(корень, описание, {"FUM-STEP": "FUM-STEP-0202"}, "Журнал/2026-09-11_01-00-00_MSK_принять-направление/запрос.md")

    def test_обновление_карточки_сохраняет_идентичность(проверка):
        with открытый_вход() as (корень, источник, решение):
            путь = корень / "Требования/🟡-пример.md"
            путь.parent.mkdir()
            старое = "# Пример\n\n<!-- FUM-REQUIREMENT-ID: FUM-REQ-0001 -->\n\nПервоначальный смысл.\n"
            путь.write_text(старое)
            описание = [{"тип": "требование", "операция": "обновить", "путь": путь.relative_to(корень).as_posix(), "ожидаемый_sha256": вход.hashlib.sha256(путь.read_bytes()).hexdigest(), "содержимое": старое + "Уточнение.\n"}]
            файлы = вход.подготовить_карточки(корень, описание, {}, "Журнал/2026-09-11_01-00-00_MSK_принять-направление/запрос.md")
            проверка.assertEqual(1, len(файлы))
            описание[0]["содержимое"] = старое.replace("FUM-REQ-0001", "FUM-REQ-0002")
            with проверка.assertRaises(ОшибкаПриёма):
                вход.подготовить_карточки(корень, описание, {}, "Журнал/2026-09-11_01-00-00_MSK_принять-направление/запрос.md")

    def test_план_пары_сохраняет_байты_и_не_пишет(проверка):
        with открытый_вход() as (корень, источник, решение):
            папка = корень / "Журнал/2026-09-11_01-00-00_MSK_принять-направление"
            папка.mkdir(parents=True)
            запрос = папка / "запрос.md"
            отчёт = папка / "отчёт.md"
            запрос.write_text("# Исходный запрос\n\n## Текст запроса\n\n```text\nРанее.\n```\n\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: " + ЗАДАЧА + "\n")
            отчёт.write_text("# Отчёт\n\nПервый результат.\n\n## Профиль времени выполнения\n\nПрофиль.\n\n## Источники\n\n- [Запрос](запрос.md)\n")
            прежде = запрос.read_bytes()
            команда = "## Идентификатор сеанса Codex\n```\nТочная команда.\n\n"
            файлы, свидетельства = вход.подготовить_пару(корень, запрос.relative_to(корень).as_posix(), ЗАДАЧА, решение["экземпляр"], команда, "Принят план.", "Граница — планирование.")
            проверка.assertEqual(прежде, запрос.read_bytes())
            for ключ, текст in (("команда", команда), ("ответ", "Принят план."), ("основание", "Граница — планирование.")):
                запись = свидетельства[ключ]
                проверка.assertEqual(текст.encode(), файлы[запись["путь"]].encode()[запись["начало"]:запись["конец"]])
            for путь, содержимое in файлы.items():
                (корень / путь).write_text(содержимое)
            повтор, повторные = вход.подготовить_пару(корень, запрос.relative_to(корень).as_posix(), ЗАДАЧА, решение["экземпляр"], команда, "Принят план.", "Граница — планирование.")
            проверка.assertEqual({}, повтор)
            проверка.assertEqual(свидетельства, повторные)


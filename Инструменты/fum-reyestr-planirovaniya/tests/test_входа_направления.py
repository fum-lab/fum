ЗАДАЧА = "00000000-0000-0000-0000-000000000201"


def строка(значение):
    return (json.dumps(значение, ensure_ascii=False) + "\n").encode()


def сообщение(текст, номер, вид="user.text"):
    return {"type": "response_item", "payload": {
        "type": "message", "role": "user", "id": str(номер),
        "content": [{"type": "input_text", "text": текст}],
        "internal_chat_message_metadata_passthrough": {"content_item_kinds": [вид]}}}


@contextmanager
def открытый_вход():
    with tempfile.TemporaryDirectory() as имя:
        корень = Path(имя).resolve() / "репозиторий"
        корень.mkdir()
        for аргументы in (("init", "-q", "-b", "codex/приём"), ("config", "user.name", "Открытая фикстура"), ("config", "user.email", "fixture@example.invalid")):
            subprocess.run(["git", *аргументы], cwd=корень, check=True, capture_output=True)
        (корень / "README.md").write_text("Открытый вход\n")
        subprocess.run(["git", "add", "."], cwd=корень, check=True)
        subprocess.run(["git", "commit", "-qm", "Основа"], cwd=корень, check=True)
        источник = корень.parent / "диалог.jsonl"
        источник.write_bytes(строка({"type": "session_meta", "payload": {"id": ЗАДАЧА}}) + строка(сообщение("Создавай отдельные задачи направлений.\n", 1)) + строка(сообщение("Направление — математика.\n", 2)))
        снимок = прочитать_вход(корень, источник, ЗАДАЧА)
        решение = {"схема": "fum.решение-приёма.1", "экземпляр": снимок["сообщения"][-1]["экземпляр"], "контекст": снимок["контекст"], "история_sha256": снимок["история_sha256"], "актуальность": "актуально", "поздние": [], "основание": "Разрешение отдельной задачи дано первым сообщением; предметная реализация не поручена.", "ответ": "Принято планирование математики.", "действие": "новое", "объём": "планирование", "задача": {"режим": "создать", "разрешение": [снимок["сообщения"][0]["экземпляр"]], "поручение": "Составить проверяемый план математики.", "projectId": "открытый-проект", "title": "Математика"}}
        yield корень, источник, решение



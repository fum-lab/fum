"""Регрессии границ свидетельства; только изолированные локальные Git-фикстуры."""
from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

СКРИПТЫ = Path(__file__).resolve().parents[1] / "scripts"
sys.path.insert(0, str(СКРИПТЫ))
from медиапакет_поддержки import собрать

ДЕНЕЖНЫЕ_ПОЛЯ = ("начальный_остаток", "поступления", "комиссии", "возвраты", "расходы")


def байты_фикстуры(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()


class ПроверкаМедиапакета(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name)
        сам.среда = {ключ: значение for ключ, значение in os.environ.items() if not ключ.startswith("GIT_")}
        сам.среда.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull,
                         GIT_AUTHOR_DATE="2026-09-15T00:00:00Z", GIT_COMMITTER_DATE="2026-09-15T00:00:00Z")
        сам.гит("init", "-q")
        сам.источник = сам.сохранить("план.txt", b"Plan fixture\n")
        сам.источник["цитата"] = "Plan fixture"
        сам.данные = {"схема": "fum.вход-медиапакета.2", "лицензия": "CC0-1.0",
                       "результат": {"вид": "план", "источник": сам.источник, "основание": None},
                       "ограничения": ["Не интегрировано."], "цель": "Поддержать ограниченный этап.",
                       "следующий_шаг": "Проверить прототип.",
                       "отчёт": {"период": None, "получатель": None, "валюта": "RUB",
                                  **dict.fromkeys(ДЕНЕЖНЫЕ_ПОЛЯ), "источник": None, "доверенный_автор": None}}

    def гит(сам, *аргументы):
        return subprocess.check_output(["git", "-c", "core.hooksPath=/dev/null", "-c", "user.name=FUM Тест",
                                        "-c", "user.email=test@example.invalid", *аргументы],
                                       cwd=сам.корень, env=сам.среда, stderr=subprocess.PIPE).decode().strip()

    def сохранить(сам, путь, содержимое):
        файл = сам.корень / путь
        файл.parent.mkdir(parents=True, exist_ok=True)
        файл.write_bytes(содержимое)
        сам.гит("add", "--", путь)
        сам.гит("commit", "--allow-empty", "-qm", "Открытая фикстура")
        return {"коммит": сам.гит("rev-parse", "HEAD"), "путь": путь,
                "sha256": hashlib.sha256(содержимое).hexdigest()}

    def финансовая_запись(сам):
        return {"схема": "fum.свидетельство-поддержки.1", "вид": "фактический учёт", "автор": "Автор фикстуры",
                "валюта": "RUB", "период": "2026-09", "получатель": "Получатель фикстуры",
                "суммы": dict(zip(ДЕНЕЖНЫЕ_ПОЛЯ, (10000, 20000, 0, 0, 3000)))}

    def с_финансами(сам, запись=None, содержимое=None):
        запись = сам.финансовая_запись() if запись is None else запись
        данные = deepcopy(сам.данные)
        данные["отчёт"].update({ключ: запись[ключ] for ключ in ("валюта", "период", "получатель")})
        данные["отчёт"].update(запись["суммы"])
        данные["отчёт"]["доверенный_автор"] = "Автор фикстуры"
        данные["отчёт"]["источник"] = сам.сохранить("учёт.json", байты_фикстуры(запись) if содержимое is None else содержимое)
        return данные

    def свидетельство_результата(сам):
        протокол = сам.сохранить("протокол.txt", "Проверена открытая фикстура; результат успешный.\n".encode())
        return {"схема": "fum.свидетельство-результата.1", "вид": "свидетельство проверки", "автор": "Автор фикстуры",
                "объект": {ключ: значение for ключ, значение in сам.источник.items() if ключ != "цитата"},
                "утверждение": сам.источник["цитата"], "проверка": "Проверка открытой фикстуры",
                "исход": "успешно", "протокол": протокол}

    def с_результатом(сам, запись=None):
        запись = сам.свидетельство_результата() if запись is None else запись
        данные = deepcopy(сам.данные)
        данные["результат"].update(вид="проверенный результат", основание={
            "доверенный_автор": "Автор фикстуры", "источник": сам.сохранить("проверка.json", байты_фикстуры(запись))})
        return данные

    def отказ(сам, данные):
        with сам.assertRaises(ValueError):
            собрать(сам.корень, данные)

    def запустить_cli(сам, содержимое):
        вход = сам.корень / "вход.json"
        вход.write_bytes(содержимое)
        return subprocess.run([sys.executable, "-B", str(СКРИПТЫ / "медиапакет-поддержки.py"),
                               "--корень-репозитория", str(сам.корень), "--вход", str(вход)],
                              env=сам.среда, capture_output=True)


    def test_отсутствующий_promisor_blob_не_дозагружается(сам):
        удалённый = сам.корень / "локальный-источник.git"
        копия = сам.корень / "частичная-копия"
        сам.гит("clone", "--bare", str(сам.корень), str(удалённый))
        копия.mkdir()
        сам.гит("-C", str(копия), "init", "-q")
        # Конечная открытая promisor-фикстура: commit и tree присутствуют,
        # ровно один blob отсутствует; источник доступен только локально.
        for выражение in ("HEAD", "HEAD^{tree}"):
            идентификатор = сам.гит("rev-parse", выражение)
            относительный = Path(".git/objects") / идентификатор[:2] / идентификатор[2:]
            (копия / относительный).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(сам.корень / относительный, копия / относительный)
        сам.гит("-C", str(копия), "update-ref", "HEAD", сам.источник["коммит"])
        сам.гит("-C", str(копия), "config", "remote.origin.url", удалённый.as_uri())
        сам.гит("-C", str(копия), "config", "remote.origin.promisor", "true")
        сам.гит("-C", str(копия), "config", "remote.origin.partialclonefilter", "blob:none")
        объект = сам.гит("rev-parse", "HEAD:план.txt")
        команда = ["git", "-C", str(копия), "cat-file", "--batch-all-objects", "--batch-check=%(objectname)"]
        сам.assertNotIn(объект, subprocess.check_output(команда, env=сам.среда).decode().splitlines())
        with сам.assertRaises(ValueError):
            собрать(копия, сам.данные)
        сам.assertNotIn(объект, subprocess.check_output(команда, env=сам.среда).decode().splitlines())
        # Положительный контроль самой фикстуры: обычный Git может получить
        # отсутствующий blob из того же локального источника после проверки.
        сам.гит("-c", "protocol.file.allow=always", "-C", str(копия), "cat-file", "-p", объект)
        сам.assertIn(объект, subprocess.check_output(команда, env=сам.среда).decode().splitlines())


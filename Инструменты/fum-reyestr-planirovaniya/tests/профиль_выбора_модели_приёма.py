"""Воспроизводимые границы явного профиля и повторов без внешнего API."""
import argparse
from contextlib import ExitStack
import hashlib
import json
import os
from pathlib import Path
import platform
import statistics
import time
import types
from unittest import mock

from test_выбора_модели_приёма import (
    открытый_вход, пакет_фикстуры, явное_решение, явный_пакет,
    подготовленная_постановка, привязать_пакет, ранний_ребёнок,
    обычный, отложенный, вход, база, нативный, ЗАДАЧА, ПАРА, ПРОИЗВОЛЬНАЯ,
)


def измерить(выход):
    if not __debug__:
        raise RuntimeError("Профиль требует включённых assert; отключите -O и PYTHONOPTIMIZE")
    каталог = Path(__file__).resolve().parents[1]
    корень_кода = каталог.parents[1]
    файлы = sorted((каталог / "scripts").glob("*.py")) + [Path(__file__)] + [
        Path(__file__).with_name(имя) for имя in ("test_выбора_модели_приёма.py", "test_входа_направления.py",
                                              "test_исполнения_приёма.py", "test_отложенных_назначений.py")]

    def отпечаток():
        return {ф.relative_to(каталог).as_posix(): hashlib.sha256(ф.read_bytes()).hexdigest() for ф in файлы}

    код_до = отпечаток()
    исходный_коммит = "f37e5d9a3e87c2a774aceeeb46825ff0b0506484"
    путь_старого = "Инструменты/fum-reyestr-planirovaniya/scripts/постановка_задачи.py"
    путь_общего = "Инструменты/fum-reyestr-planirovaniya/scripts/приём_направления.py"
    старый_код = обычный.хранилище.гит(корень_кода, "show", исходный_коммит + ":" + путь_старого, сырые=True)
    общий_код = обычный.хранилище.гит(корень_кода, "show", исходный_коммит + ":" + путь_общего, сырые=True)
    assert общий_код == (корень_кода / путь_общего).read_bytes(), "Общая зависимость отличается от исторического кода"
    историческая = types.ModuleType("историческая_постановка_задачи")
    exec(compile(старый_код, исходный_коммит + ":" + путь_старого, "exec"), историческая.__dict__)
    события, итоги = [], []
    глубина = 0
    повтор, сценарий = 0, ""

    def замерить(имя, операция, *аргументы, **параметры):
        nonlocal глубина
        начало, уровень = time.perf_counter_ns(), глубина
        глубина += 1
        исход = "ошибка"
        try:
            результат = операция(*аргументы, **параметры)
            исход = "успех"
            return результат
        finally:
            глубина -= 1
            события.append({"повтор": повтор, "сценарий": сценарий, "стадия": имя,
                "глубина": уровень, "наносекунды": time.perf_counter_ns() - начало, "исход": исход})

    def метки(исполнитель):
        стек = ExitStack()
        for объект, имя, метка in ((вход, "проверить_профиль", "форма пары"),
                (исполнитель, "_аргументы", "генератор аргументов"),
                (исполнитель.хранилище, "начать_попытку", "долговечная попытка")):
            операция = getattr(объект, имя)
            стек.enter_context(mock.patch.object(объект, имя, side_effect=
                lambda *а, операция=операция, метка=метка, **к: замерить(метка, операция, *а, **к)))
        return стек

    for повтор in range(1, 4):
        сценарий = "обычное создание"
        with открытый_вход() as (корень, источник, решение):
            явное_решение(решение, ПРОИЗВОЛЬНАЯ)
            исполнитель, результат, коммит, ветка = подготовленная_постановка(корень, источник, решение)
            with mock.patch.object(обычный, "проверить_инструменты"):
                исполнитель.закрепить_постановку(результат["событие"], коммит, ветка)
                with метки(исполнитель):
                    допуск = замерить("первый допуск целиком", исполнитель.допустить_вызов, источник, ЗАДАЧА, решение)
            assert {ключ: допуск["аргументы"][ключ] for ключ in ПРОИЗВОЛЬНАЯ} == ПРОИЗВОЛЬНАЯ
            ребёнок, задача, нативный_источник = ранний_ребёнок(корень, коммит, допуск, ПРОИЗВОЛЬНАЯ, 701, явный=True)
            замерить("нативное наблюдение целиком", исполнитель.наблюдать, допуск["событие"], ребёнок, задача, нативный_источник)
            до = исполнитель.хранилище.путь.read_bytes()
            with mock.patch.object(исполнитель, "_аргументы", side_effect=AssertionError("Повтор не вызывает генератор")):
                for _ in range(5):
                    assert not замерить("повтор целиком", исполнитель.допустить_вызов, источник, ЗАДАЧА, решение)["разрешён_вызов"]
            assert исполнитель.хранилище.путь.read_bytes() == до
            итоги.append({"повтор": повтор, "сценарий": сценарий, "первые_попытки": 1, "повторы": 5,
                          "повторных_генераций": 0, "равные_байты_состояния": True})

        сценарий = "шесть отложенных строк"
        with пакет_фикстуры(6) as (корень, пакет):
            явный_пакет(пакет)
            исполнитель = отложенный.ИсполнительНазначений(корень, ЗАДАЧА)
            план, коммит = привязать_пакет(исполнитель, корень, пакет)
            with mock.patch.object(обычный, "проверить_инструменты"), метки(исполнитель):
                for часть in пакет["назначения"]:
                    допуск = замерить("первый допуск целиком", исполнитель.допустить, пакет, часть["направление"])
                    assert {ключ: допуск["аргументы"][ключ] for ключ in ПАРА} == {ключ: часть["задача"][ключ] for ключ in ПАРА}
            до = исполнитель.хранилище.путь.read_bytes()
            with mock.patch.object(исполнитель, "_аргументы", side_effect=AssertionError("Повтор не вызывает генератор")):
                for часть in пакет["назначения"]:
                    assert not замерить("повтор целиком", исполнитель.допустить, пакет, часть["направление"])["разрешён_вызов"]
            assert исполнитель.хранилище.путь.read_bytes() == до
            итоги.append({"повтор": повтор, "сценарий": сценарий, "первые_попытки": 6, "повторы": 6,
                          "повторных_генераций": 0, "равные_байты_состояния": True})

        # Обе реализации читают одни и те же байты по общему историческому контракту.
        # Производитель C244 и подготовка Git/JSONL остаются вне измеряемых интервалов.
        with открытый_вход() as (корень, источник, решение):
            _, _, коммит, _ = подготовленная_постановка(корень, источник, решение)
            for с_поручением in (False, True):
                сценарий = "чтение исторической квитанции ." + ("2" if с_поручением else "1")
                номер = 801 + int(с_поручением)
                ребёнок = корень.parent / ("ребёнок-" + str(номер))
                задача = f"00000000-0000-0000-0000-{номер:012d}"
                обычный.хранилище.гит(корень, "worktree", "add", "-b", "codex/ребёнок-" + str(номер), str(ребёнок), коммит)
                нативный_источник = корень.parent / ("нативный-" + str(номер) + ".jsonl")
                нативный(ребёнок, нативный_источник, коммит, {"model": "gpt-6-astra", "thinking": "low"},
                         задача=задача, поручение="Первоначальное поручение ROOT" if с_поручением else None)
                ожидаемое = историческая.подтвердить_начало(ребёнок, задача, коммит, нативный_источник, с_поручением=с_поручением)
                квитанция = историческая.путь_подтверждения(ребёнок)
                байты_квитанции, байты_источника = квитанция.read_bytes(), нативный_источник.read_bytes()
                for пара_порядка in ((историческая, база), (база, историческая), (историческая, база)):
                    for читатель in пара_порядка:
                        имя = "исторический читатель C244" if читатель is историческая else "текущий читатель"
                        assert замерить(имя, читатель.прочитать_подтверждение, ребёнок, задача, коммит, нативный_источник) == ожидаемое
                        assert квитанция.read_bytes() == байты_квитанции
                        assert нативный_источник.read_bytes() == байты_источника
                итоги.append({"повтор": повтор, "сценарий": сценарий, "парные_чтения": 3,
                              "равные_результаты": True, "равные_байты_квитанции_и_JSONL": True,
                              "sha256_квитанции": hashlib.sha256(байты_квитанции).hexdigest(),
                              "sha256_JSONL": hashlib.sha256(байты_источника).hexdigest()})

    стадии = [{"сценарий": сценарий, "стадия": имя, "число": len(замеры),
               "медиана_мс": statistics.median(замеры) / 1e6}
        for сценарий, имя in sorted({(э["сценарий"], э["стадия"]) for э in события})
        for замеры in [[э["наносекунды"] for э in события if (э["сценарий"], э["стадия"]) == (сценарий, имя)]]]
    код_после = отпечаток()
    assert код_до == код_после, "Состав кода изменился во время профиля"
    данные = {"схема": "fum.профиль-выбора-модели-приёма.2", "версия_питона": platform.python_version(),
        "система": platform.system(), "архитектура": platform.machine(), "запуск": os.environ.get("FUM_CHECK_RUN_ID"),
        "код_до": код_до, "код_после": код_после,
        "исторический_код": {"коммит": исходный_коммит, "путь": путь_старого,
            "sha256": hashlib.sha256(старый_код).hexdigest(), "общая_зависимость": путь_общего,
            "sha256_общей_зависимости": hashlib.sha256(общий_код).hexdigest(),
            "пара": {"model": "gpt-6-astra", "thinking": "low"}},
        "пары": [ПАРА, ПРОИЗВОЛЬНАЯ], "повторы": итоги, "события": события, "стадии": стадии,
        "граница": "Три независимые открытые Git/JSONL-фикстуры каждого сценария. Подготовка, коммиты и ранняя квитанция вне интервала; допуск, долговечная попытка, наблюдение и повтор измерены отдельно. Парное сравнение C244 и текущего кода ограничено общим контрактом чтения неизменной исторической квитанции .1/.2 и того же JSONL; порядок A/B, B/A, A/B. Оно не сравнивает первое создание и отложенный допуск с прежней реализацией. Метки оборачивают исходные функции; вложенные интервалы не суммируются. Проверка полного FUM-кода и реестра подменена только из-за минимального состава фикстур. MCP, сеть и большой рабочий JSONL не измерены.",
        "критерий": "Точное равенство пары и байтов состояния; ноль генераций на повторе. Оптимизация допустима лишь при измеренном преобладании новой проверки формы над долговечным допуском; сравнение разных стадий не является заявлением об ускорении."}
    Path(выход).parent.mkdir(parents=True, exist_ok=True)
    Path(выход).write_text(json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + "\n")
    print(json.dumps(стадии, ensure_ascii=False))


if __name__ == "__main__":
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--выход", required=True)
    измерить(парсер.parse_args().выход)

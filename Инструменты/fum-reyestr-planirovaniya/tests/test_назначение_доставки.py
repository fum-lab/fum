"""Явное назначение постоянной ветки и наблюдение без исполнения доставки."""
import copy
import hashlib
import json
from pathlib import Path
import sys
import subprocess
import shlex
import tempfile
import unittest

from test_обратная_доставка import Фикстура, гит, ЗАДАЧА, КООРДИНАТОР
from приём_направления import ОшибкаПриёма, байты
import доставка_план as планы

КОРНЕВАЯ_ЗАДАЧА = "01a07d3d-d376-7ad2-aafc-67e4c25a67eb"


def назначить(фикстура, источник=False):
    корень = фикстура.источник if источник else фикстура.цель
    владелец = КООРДИНАТОР if источник else ЗАДАЧА
    гит(корень, "branch", "-m", "fuma")
    назначение = {"корень": str(корень), "ref": "refs/heads/fuma", "владелец": владелец,
                  "корневая_задача": КОРНЕВАЯ_ЗАДАЧА}
    фикстура.владельцы[str(корень)] = {"задача": владелец, "ref": "refs/heads/fuma",
                                    "корневая_задача": КОРНЕВАЯ_ЗАДАЧА}
    фикстура.реестр.write_bytes(байты(фикстура.владельцы))
    if источник:
        фикстура.описание["ref"] = "refs/heads/fuma"
    return назначение


class ПроверкиНазначения(unittest.TestCase):
    def __init__(сам, *аргументы, **именованные):
        super().__init__(*аргументы, **именованные)
        временное = tempfile.TemporaryDirectory(prefix="fum-назначение-")
        сам.addCleanup(временное.cleanup)
        сам.ф = Фикстура(временное.name)

    def план(сам, назначение):
        return планы.построить_план(сам.ф.описание, [str(сам.ф.цель)], сам.ф.владельцы,
                                    назначение=назначение)

    def test_источник_из_отсоединённого_каталога_не_владеет_веткой(сам):
        гит(сам.ф.источник, "branch", "-m", "fuma")
        сам.ф.описание["ref"] = "refs/heads/fuma"
        старый = сам.ф.папка / "fuma"
        гит(сам.ф.источник, "worktree", "add", "--detach", str(старый), сам.ф.описание["коммит"])
        сам.ф.описание["корень"] = str(старый)
        with сам.assertRaises(ОшибкаПриёма):
            сам.ф.план()

    def test_основная_ветка_не_становится_допустимым_источником(сам):
        гит(сам.ф.источник, "branch", "-m", "master")
        сам.ф.описание["ref"] = "refs/heads/master"
        with сам.assertRaises(ОшибкаПриёма):
            сам.ф.план()

    def test_назначенный_получатель_проходит_весь_цикл(сам):
        назначение = назначить(сам.ф)
        план = сам.план(назначение)
        сам.assertEqual(план["схема"], "fum.план-обратной-доставки.2")
        сам.assertEqual(планы.проверить_план(план), план)
        with сам.ф.владелец(план) as доставка:
            сам.assertEqual(доставка.применить()["стадия"], "применено")
            сам.assertEqual(доставка.проверить([sys.executable, "-c", "print('проверка')"])["стадия"], "проверено")
            гит(сам.ф.цель, "commit", "-m", "Доставить срез")
            доставка.подтвердить_коммит()
            сам.assertEqual(доставка.подтвердить_получение("Открытая проверка выполнена")["получатель"], "подтверждено")

    def test_назначенный_источник_и_обе_идентичности_поручения(сам):
        назначение = назначить(сам.ф, источник=True)
        план = сам.план(назначение)
        сам.assertEqual(планы.поручения(план)[0]["корневая_задача"], КОРНЕВАЯ_ЗАДАЧА)
        сам.assertEqual(планы.поручения(план)[0]["threadId"], ЗАДАЧА)
        with сам.ф.владелец(план) as доставка:
            сам.assertEqual(доставка.применить()["стадия"], "применено")

    def test_отсоединённый_одноимённый_каталог_не_подменяет_назначение(сам):
        назначение = назначить(сам.ф, источник=True)
        старый = сам.ф.папка / "fuma"
        гит(сам.ф.источник, "worktree", "add", "--detach", str(старый), сам.ф.описание["коммит"])
        сам.план(назначение)
        сам.ф.описание["корень"] = str(старый)
        with сам.assertRaises(ОшибкаПриёма):
            сам.план(назначение)

    def test_нет_неявного_допуска_и_подмены_назначения(сам):
        назначение = назначить(сам.ф)
        with сам.assertRaises(ОшибкаПриёма):
            сам.ф.план()
        for ключ, значение in (("корневая_задача", ЗАДАЧА), ("владелец", КООРДИНАТОР),
                               ("корень", str(сам.ф.источник)), ("ref", "refs/heads/master")):
            with сам.subTest(ключ=ключ), сам.assertRaises(ОшибкаПриёма):
                сам.план({**назначение, ключ: значение})

    def test_смена_назначения_после_плана_останавливает_эффект(сам):
        план = сам.план(назначить(сам.ф))
        сам.ф.владельцы[str(сам.ф.цель)]["задача"] = КООРДИНАТОР
        сам.ф.реестр.write_bytes(байты(сам.ф.владельцы))
        with сам.ф.владелец(план) as доставка, сам.assertRaises(ОшибкаПриёма):
            доставка.применить()
        сам.assertEqual(гит(сам.ф.цель, "status", "--porcelain"), "")
        сам.assertEqual(гит(сам.ф.цель, "rev-parse", "HEAD"), сам.ф.вершина)

    def test_наблюдение_читает_недоставку_и_не_создаёт_квитанции(сам):
        план = сам.план(назначить(сам.ф))
        до = {str(п): hashlib.sha256(п.read_bytes()).hexdigest() for п in сам.ф.папка.rglob("*") if п.is_file()}
        сигнал = планы.наблюдать_назначение(план, сам.ф.владельцы, порог_коммитов=1)
        сам.assertEqual(сигнал["получатели"][0]["отсутствующих_коммитов"], 1)
        сам.assertEqual(сигнал["получатели"][0]["ожидание_секунд"], "unknown")
        сам.assertTrue(сигнал["получатели"][0]["порог_достигнут"])
        сам.assertEqual(сигнал["получатели"][0]["получатель"], "unknown")
        сам.assertEqual(до, {str(п): hashlib.sha256(п.read_bytes()).hexdigest() for п in сам.ф.папка.rglob("*") if п.is_file()})
        гит(сам.ф.цель, "merge", "--no-edit", сам.ф.срез)
        сигнал = планы.наблюдать_назначение(план, сам.ф.владельцы)
        сам.assertFalse(сигнал["план_актуален"])
        сам.assertEqual(сигнал["получатели"][0]["отсутствующих_коммитов"], 0)
        сам.assertEqual(сигнал["получатели"][0]["отношение"], "в предках")
        сам.assertEqual(сигнал["получатели"][0]["получатель"], "unknown")

    def test_устаревшее_назначение_даёт_неизвестность(сам):
        план = сам.план(назначить(сам.ф))
        изменённые = copy.deepcopy(сам.ф.владельцы)
        изменённые[str(сам.ф.цель)]["задача"] = КООРДИНАТОР
        сигнал = планы.наблюдать_назначение(план, изменённые)
        сам.assertFalse(сигнал["план_актуален"])
        сам.assertEqual(сигнал["получатели"][0]["отношение"], "unknown")
        сам.assertEqual(сигнал["получатели"][0]["отсутствующих_коммитов"], "unknown")
        сам.assertIn("реестр", сигнал["получатели"][0]["причина_ожидания"])

    def test_командная_строка_строит_план_и_компактное_наблюдение(сам):
        назначение = назначить(сам.ф)
        вход = сам.ф.папка / "вход.json"
        вход.write_bytes(байты({"источник": сам.ф.описание, "получатели": [str(сам.ф.цель)],
                               "владельцы": str(сам.ф.реестр), "назначение": назначение}))
        исполнитель = Path(__file__).resolve().parents[1] / "scripts" / "обратная-доставка.py"
        результат = subprocess.run([sys.executable, "-B", str(исполнитель), "наблюдать", "--вход", str(вход)], capture_output=True, check=True)
        план = сам.ф.папка / "план.json"
        план.write_bytes(результат.stdout)
        результат = subprocess.run([sys.executable, "-B", str(исполнитель), "назначение", "--план", str(план),
                                     "--владельцы", str(сам.ф.реестр), "--порог-коммитов", "1"], capture_output=True, check=True)
        сам.assertEqual(результат.stderr, b"")
        сам.assertTrue(json.loads(результат.stdout)["план_актуален"])
        сам.assertLess(len(результат.stdout), 4096)

    def test_смена_дерева_с_сохранённой_веткой_не_передаёт_квитанцию(сам):
        план = сам.план(назначить(сам.ф))
        гит(сам.ф.цель, "checkout", "--detach")
        новый = сам.ф.папка / "новое-дерево"
        гит(сам.ф.источник, "worktree", "add", str(новый), "fuma")
        сигнал = планы.наблюдать_назначение(план, сам.ф.владельцы)
        сам.assertEqual(сигнал["получатели"][0]["отношение"], "unknown")
        with сам.ф.владелец(план) as доставка, сам.assertRaises(ОшибкаПриёма):
            доставка.применить()
        сам.assertFalse((сам.ф.папка / "состояние").exists())

    def test_сдвиг_источника_делает_наблюдение_неизвестным(сам):
        план = сам.план(назначить(сам.ф, источник=True))
        сам.ф.записать(сам.ф.источник, "позднее.txt", "новый этап\n")
        сам.ф.коммит(сам.ф.источник)
        сигнал = планы.наблюдать_назначение(план, сам.ф.владельцы)
        сам.assertFalse(сигнал["план_актуален"])
        сам.assertEqual(сигнал["получатели"][0]["сигнал_недоставки"], "unknown")

    def test_грязная_ветка_даёт_причину_ожидания_и_сохраняет_данные(сам):
        план = сам.план(назначить(сам.ф))
        сам.ф.записать(сам.ф.цель, "работа.txt", "незавершённое\n")
        сигнал = планы.наблюдать_назначение(план, сам.ф.владельцы)
        сам.assertIn("рабочая разница", сигнал["получатели"][0]["причина_ожидания"])
        сам.assertEqual((сам.ф.цель / "работа.txt").read_text(), "незавершённое\n")
        сам.assertEqual(сигнал["получатели"][0]["отсутствующих_коммитов"], 1)

    def test_подмена_корневой_задачи_отчёта_отклоняется_до_записи(сам):
        план = сам.план(назначить(сам.ф))
        with сам.ф.владелец(план) as доставка, сам.assertRaises(ОшибкаПриёма):
            доставка.проверить([sys.executable, "-c", "print('лишний запуск')"], запрос="запрос.md", корневая_задача=ЗАДАЧА)
        сам.assertFalse((сам.ф.папка / "состояние").exists())

    def test_перехэширование_не_расширяет_схему_допуска(сам):
        from приём_направления import хэш
        план = сам.план(назначить(сам.ф))
        for изменение in ("старый формат", "чужая ветка", "лишнее поле"):
            другой = copy.deepcopy(план)
            if изменение == "старый формат":
                другой["схема"] = "fum.план-обратной-доставки.1"
                del другой["назначение"]
            elif изменение == "чужая ветка":
                другой["назначение"]["ref"] = "refs/heads/master"
                другой["получатели"][0]["ref"] = "refs/heads/master"
            else:
                другой["назначение"]["разрешить_всё"] = True
            другой["идентификатор"] = хэш({ключ: значение for ключ, значение in другой.items() if ключ != "идентификатор"})
            with сам.subTest(изменение=изменение), сам.assertRaises(ОшибкаПриёма):
                планы.проверить_план(другой)

    def test_наблюдение_не_запускает_очищающий_фильтр(сам):
        сам.ф.записать(сам.ф.цель, ".gitattributes", "работа.txt filter=маркер\n")
        сам.ф.коммит(сам.ф.цель)
        план = сам.план(назначить(сам.ф))
        маркер = сам.ф.папка / "фильтр-запущен"
        код = "from pathlib import Path; import sys; Path(" + repr(str(маркер)) + ").touch(); sys.stdout.buffer.write(sys.stdin.buffer.read())"
        гит(сам.ф.цель, "config", "filter.маркер.clean", shlex.join([sys.executable, "-c", код]))
        сам.ф.записать(сам.ф.цель, "работа.txt", "изменено\n")
        сигнал = планы.наблюдать_назначение(план, сам.ф.владельцы)
        сам.assertFalse(маркер.exists())
        сам.assertIn("фильтр", сигнал["получатели"][0]["причина_ожидания"])

    def test_наблюдение_не_запускает_фильтр_зависимости(сам):
        from test_обратная_доставка import ПроверкиДоставки
        вложенный = ПроверкиДоставки._подготовить_зависимость(сам)
        план = сам.план(назначить(сам.ф))
        маркер = сам.ф.папка / "вложенный-фильтр-запущен"
        код = "from pathlib import Path; import sys; Path(" + repr(str(маркер)) + ").touch(); sys.stdout.buffer.write(sys.stdin.buffer.read())"
        гит(вложенный, "config", "filter.маркер.clean", shlex.join([sys.executable, "-c", код]))
        (вложенный / ".gitattributes").write_text("код.txt filter=маркер\n")
        (вложенный / "код.txt").write_text("изменённая зависимость\n")
        сигнал = планы.наблюдать_назначение(план, сам.ф.владельцы)
        сам.assertFalse(маркер.exists())
        сам.assertIn("фильтр", сигнал["получатели"][0]["причина_ожидания"])


if __name__ == "__main__":
    unittest.main()

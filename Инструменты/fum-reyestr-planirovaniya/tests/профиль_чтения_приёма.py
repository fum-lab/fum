"""Сопоставимый профиль подготовки на открытом неизменном JSONL."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import time
from unittest import mock

from test_входа_направления import открытый_вход, ЗАДАЧА, строка
from test_исполнения_приёма import журнал
import исполнитель_приёма as исполнение


def измерить(переиспользовать):
    with открытый_вход() as (корень, источник, решение):
        with источник.open("ab") as поток:
            for _ in range(2000):
                поток.write(строка({"type": "event_msg", "payload": {"type": "token_count", "info": {"открытая_фикстура": "я" * 128}}}))
        запрос = журнал(корень)
        решение["действие"] = "обновить"
        читатель = исполнение.вход.обработка.читатель
        снимок = читатель._прочитать_снимок
        остаток = исполнение.вход.обработка.получить_остаток
        профили, вычислений = [], 0
        def прочитать(*аргументы, **параметры):
            результат = снимок(*аргументы, **параметры)
            профили.append(результат[0]["профиль"])
            return результат
        def вычислить(*аргументы, **параметры):
            nonlocal вычислений
            вычислений += 1
            if not переиспользовать:
                параметры.pop("чтение", None)
            return остаток(*аргументы, **параметры)
        with mock.patch.object(читатель, "_прочитать_снимок", side_effect=прочитать), mock.patch.object(исполнение.вход.обработка, "получить_остаток", side_effect=вычислить), mock.patch.object(исполнение, "проверить_планирование", return_value="{}\n"):
            начало = time.perf_counter_ns()
            результат = исполнение.ИсполнительПриёма(корень, ЗАДАЧА).подготовить(источник, ЗАДАЧА, решение, запрос, [])
            длительность = time.perf_counter_ns() - начало
        assert результат["готов"]
        return {"байтов_источника": источник.stat().st_size, "вычислений_остатка": вычислений,
                "чтений_снимка": len(профили), "длительность_наносекунды": длительность,
                "прочитано_байтов": sum(п["прочитано_байтов"] for п in профили),
                "разобрано_строк": sum(п["разобрано_строк"] for п in профили),
                "режимы": [п["режим"] for п in профили],
                "сверка_снимка_наносекунды": sum(п["сверка_снимка_наносекунды"] for п in профили),
                "чтение_источника_наносекунды": sum(п["этапы_наносекунды"]["чтение_источника"] for п in профили)}


def главный():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--выход", required=True)
    параметры = парсер.parse_args()
    начало = time.perf_counter_ns()
    измерения = {"отдельные-сеансы": [], "общий-сеанс": []}
    for повтор in range(3):
        for общий in ((False, True) if повтор % 2 == 0 else (True, False)):
            измерения["общий-сеанс" if общий else "отдельные-сеансы"].append(измерить(общий))
    файлы = [Path(__file__), Path(исполнение.__file__), Path(исполнение.вход.__file__),
             Path(исполнение.вход.обработка.__file__), Path(исполнение.вход.обработка.читатель.__file__)]
    результат = {"схема": "fum.профиль-чтения-приёма.1", "python": platform.python_version(),
                 "код": {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in файлы},
                 "измерения": измерения, "полное_время_наблюдения_наносекунды": time.perf_counter_ns() - начало,
                 "граница": "Шесть независимых открытых фикстур, три пары с чередованием порядка. Реальные Git, JSONL, подготовка и свежие сверки. Сборщик реестра заменён подстановкой. Базовый режим создаёт отдельный штатный сеанс каждого остатка, общий режим сохраняет сеанс подготовки. Подготовка фикстуры исключена из длительности операции, включена в полное время наблюдения. Счётчики байтов относятся только к чтениям снимков, исключают отдельные сверить_границы; общая длительность включает их. Время чтения включает разбор и сверку: отдельно время разбора не измерялось. Сбор профилей включён, его отдельная цена неизвестна. Память, деньги и токены модели не измерены; вывод не распространяется на живой изменяющийся JSONL."}
    Path(параметры.выход).write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({имя: [{к: з for к, з in замер.items() if к in {"прочитано_байтов", "разобрано_строк", "длительность_наносекунды"}} for замер in замеры] for имя, замеры in измерения.items()}, ensure_ascii=False))


if __name__ == "__main__":
    главный()

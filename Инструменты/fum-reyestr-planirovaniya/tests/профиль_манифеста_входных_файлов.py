"""Повторяемый профиль чтения десяти обычных Git-входов, без сети и Desktop."""
import argparse
import hashlib
import json
from pathlib import Path
import statistics
import time
from unittest import mock

from test_манифеста_входных_файлов import снимок_фикстуры, назначения, ХЭШ_МОДУЛЯ as ФИКСТУРА_SHA256

ПУТЬ_ФИКСТУРЫ = Path(__file__).with_name("test_манифеста_входных_файлов.py")
ПРОФИЛЬ_SHA256 = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def сверить_код():
    for путь, ожидаемый in ((Path(назначения.__file__), назначения.ХЭШ_МОДУЛЯ),
                            (ПУТЬ_ФИКСТУРЫ, ФИКСТУРА_SHA256),
                            (Path(__file__), ПРОФИЛЬ_SHA256)):
        if hashlib.sha256(путь.read_bytes()).hexdigest() != ожидаемый:
            raise RuntimeError("Изменён код профиля: " + путь.name)


def выполнить(повторов):
    сверить_код()
    наблюдения = []
    with снимок_фикстуры() as (корень, коммит, файлы, данные):
        исходное_чтение = назначения.гит
        for _ in range(повторов):
            стадии = {"тип_коммита": 0, "поиск_blob": 0, "чтение_blob": 0}
            вызовов = dict.fromkeys(стадии, 0)

            def измерить(корень_входа, *аргументы, **параметры):
                стадия = ("поиск_blob" if аргументы[0] == "ls-tree"
                          else "тип_коммита" if аргументы[1] == "-t" else "чтение_blob")
                начало = time.perf_counter_ns()
                try:
                    return исходное_чтение(корень_входа, *аргументы, **параметры)
                finally:
                    стадии[стадия] += time.perf_counter_ns() - начало
                    вызовов[стадия] += 1

            начало = time.perf_counter_ns()
            with mock.patch.object(назначения, "гит", side_effect=измерить):
                прочитано = назначения.манифест_коммита(корень, коммит, файлы)
            всего = time.perf_counter_ns() - начало
            assert прочитано == данные
            assert вызовов == {"тип_коммита": 1, "поиск_blob": 10, "чтение_blob": 10}
            наблюдения.append({"всего_ns": всего, "Git_ns": стадии, "Git_вызовов": вызовов,
                                "проверка_пути_SHA_и_измерительная_обёртка_ns": всего - sum(стадии.values())})
    сверить_код()
    return {
        "схема": "fum.профиль-входного-манифеста.1",
        "входов": 10,
        "повторов": повторов,
        "медиана_ns": int(statistics.median(запись["всего_ns"] for запись in наблюдения)),
        "наблюдения": наблюдения,
        "код_sha256": назначения.ХЭШ_МОДУЛЯ,
        "фикстура_sha256": ФИКСТУРА_SHA256,
        "профиль_sha256": ПРОФИЛЬ_SHA256,
        "граница": "Только чтение обычных blobs закреплённого коммита. Создание фикстуры, JSONL корня, сеть и Desktop исключены. Измерительная обёртка включена в общее время.",
        "сравнение": "Прежний читатель отказывал на этих входах; завершённый прежний замер отсутствует. Ускорение не заявляется.",
    }


if __name__ == "__main__":
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--повторов", type=int, default=5)
    парсер.add_argument("--выход", required=True)
    аргументы = парсер.parse_args()
    if not 1 <= аргументы.повторов <= 20:
        парсер.error("Число повторов должно быть от 1 до 20")
    итог = выполнить(аргументы.повторов)
    текст = json.dumps(итог, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    with Path(аргументы.выход).open("x", encoding="utf-8") as поток:
        поток.write(текст)
    print(json.dumps({"медиана_ns": итог["медиана_ns"], "входов": итог["входов"], "повторов": итог["повторов"]}, ensure_ascii=False))

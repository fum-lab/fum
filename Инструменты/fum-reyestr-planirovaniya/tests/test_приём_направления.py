    def test_смена_ref_между_намерением_и_записью_закрывает_запись(проверка):
        исходная = проверка.хранилище.изменить
        переключено = False
        @contextmanager
        def вмешаться():
            nonlocal переключено
            with исходная() as состояние:
                yield состояние
            if not переключено and состояние["этапы"]:
                переключено = True
                проверка.гит("switch", "-qc", "codex/другой-ref")
        with mock.patch.object(проверка.хранилище, "изменить", вмешаться):
            with проверка.assertRaises(ПРИЁМ.ОшибкаПриёма):
                проверка.хранилище.применить_файлы("а", "этап", {"Планирование/а.md": "а"})
        проверка.assertFalse((проверка.корень / "Планирование/а.md").exists())


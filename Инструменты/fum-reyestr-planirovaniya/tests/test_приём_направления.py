    def test_частичная_запись_продолжается_без_перезаписи_чужих_байтов(проверка):
        первый = "Планирование/а.md"
        второй = "Планирование/б.md"
        файлы = {первый: "первая карточка\n", второй: "вторая карточка\n"}
        исходная = ПРИЁМ.установить
        def оборвать(путь, данные):
            if путь == проверка.корень / второй:
                raise OSError("Открытая фикстура прерывания")
            исходная(путь, данные)
        with mock.patch.object(ПРИЁМ, "установить", side_effect=оборвать):
            with проверка.assertRaises(OSError):
                проверка.хранилище.применить_файлы("событие", "карточки", файлы)
        проверка.assertTrue((проверка.корень / первый).exists())
        проверка.хранилище.применить_файлы("событие", "карточки", файлы)
        проверка.assertEqual("вторая карточка\n", (проверка.корень / второй).read_text())
        (проверка.корень / первый).write_text("чужая правка")
        with проверка.assertRaises(ПРИЁМ.ОшибкаПриёма):
            проверка.хранилище.применить_файлы("событие", "карточки", файлы)


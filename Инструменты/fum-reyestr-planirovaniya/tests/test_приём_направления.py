    def test_вложенная_схема_отклоняет_перехэшированные_ошибки(проверка):
        проверка.хранилище.выделить("а", ["FUM-STEP"], "источник")
        проверка.хранилище.начать_попытку("а", {"prompt": "план"})
        проверка.хранилище.применить_файлы("а", "карточки", {"Планирование/а.md": "а"})
        исходное = json.loads(проверка.хранилище.путь.read_bytes())["данные"]
        def неверный_вид(состояние):
            состояние["резервы"]["а"]["номера"]["FUM-STEP"] = "FUM-REQ-0001"
        def повтор_владения(состояние):
            состояние["резервы"]["б"] = dict(состояние["резервы"]["а"])
        def потерянный_номер(состояние):
            состояние["занятые"] = []
        def ложная_готовность(состояние):
            next(iter(состояние["этапы"].values()))["готов"] = "нет"
        def подменённые_аргументы(состояние):
            состояние["попытки"]["а"]["аргументы"] = {"prompt": "другое"}
        def неизвестное_поле(состояние):
            состояние["попытки"]["а"]["лишнее"] = True
        for испортить in (неверный_вид, повтор_владения, потерянный_номер, ложная_готовность, подменённые_аргументы, неизвестное_поле):
            with проверка.subTest(случай=испортить.__name__):
                состояние = json.loads(json.dumps(исходное))
                испортить(состояние)
                проверка.записать_состояние(состояние)
                до = проверка.хранилище.путь.read_bytes()
                with проверка.assertRaises(ПРИЁМ.ОшибкаПриёма):
                    проверка.хранилище.выделить("а", ["FUM-STEP"], "источник")
                проверка.assertEqual(до, проверка.хранилище.путь.read_bytes())
        проверка.записать_состояние(исходное)


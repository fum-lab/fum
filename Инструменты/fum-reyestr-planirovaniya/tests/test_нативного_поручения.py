"""Точный наблюдённый транспорт поручения и граница сырых байтов."""
import hashlib
import json
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from постановка_задачи import проверить_нативное_поручение
from приём_направления import ОшибкаПриёма

ОТПРАВИТЕЛЬ = "00000000-0000-0000-0000-000000000201"
ПОРУЧЕНИЕ = "Проверь <свой UUID> & x > 0; &lt;буквально&gt; и <b>ё</b>."
ТЕКСТ_ТРАНСПОРТА = "Проверь &lt;свой UUID&gt; &amp; x &gt; 0; &amp;lt;буквально&amp;gt; и &lt;b&gt;ё&lt;/b&gt;."


def конверт(текст=ТЕКСТ_ТРАНСПОРТА, отправитель=ОТПРАВИТЕЛЬ):
    return "<codex_delegation>\n  <source_thread_id>" + отправитель + "</source_thread_id>\n  <input>" + текст + "</input>\n</codex_delegation>"


def строка(данные):
    return (json.dumps(данные, ensure_ascii=False) + "\n").encode("utf-8")


def нативная_запись(текст=ТЕКСТ_ТРАНСПОРТА, отправитель=ОТПРАВИТЕЛЬ):
    return строка({"type": "response_item", "payload": {"type": "function_call_output", "name": "create_thread", "output": конверт(текст, отправитель)}})


class ПроверкаНативногоПоручения(unittest.TestCase):
    def источник(проверка, данные):
        временный = tempfile.TemporaryDirectory()
        проверка.addCleanup(временный.cleanup)
        путь = Path(временный.name).resolve() / "начало.jsonl"
        путь.write_bytes(данные)
        return путь

    def отклонить(проверка, данные, поручение=ПОРУЧЕНИЕ):
        with проверка.assertRaisesRegex(ОшибкаПриёма, "точное первоначальное нативное поручение"):
            проверить_нативное_поручение(проверка.источник(данные), ОТПРАВИТЕЛЬ, поручение)

    def test_единственное_экранирование_и_хэш_сырого_префикса(проверка):
        префикс = строка({"type": "session_meta", "payload": {"id": "открытая фикстура"}}) + нативная_запись()
        путь = проверка.источник(префикс + b"not JSON: untouched tail")
        проверка.assertEqual({"граница": len(префикс), "sha256": hashlib.sha256(префикс).hexdigest()},
                            проверить_нативное_поручение(путь, ОТПРАВИТЕЛЬ, ПОРУЧЕНИЕ))

    def test_буквальная_сущность_отличается_от_угловой_скобки(проверка):
        путь = проверка.источник(нативная_запись("&amp;lt;x&amp;gt;"))
        проверить_нативное_поручение(путь, ОТПРАВИТЕЛЬ, "&lt;x&gt;")
        проверка.отклонить(нативная_запись("&lt;x&gt;"), "&lt;x&gt;")

    def test_сырой_и_другие_способы_экранирования_отклоняются(проверка):
        for текст in (ПОРУЧЕНИЕ, ТЕКСТ_ТРАНСПОРТА.replace("&", "&amp;"),
                      ТЕКСТ_ТРАНСПОРТА.replace("&amp; x", "& x"),
                      ТЕКСТ_ТРАНСПОРТА.replace("&lt;", "&#60;")):
            with проверка.subTest(текст=текст):
                проверка.отклонить(нативная_запись(текст))

    def test_чужой_отправитель_отклоняется(проверка):
        проверка.отклонить(нативная_запись(отправитель="00000000-0000-0000-0000-000000000999"))

    def test_изменённый_внешний_конверт_отклоняется(проверка):
        данные = {"type": "response_item", "payload": {"type": "function_call_output", "name": "create_thread", "output": конверт() + "\n"}}
        проверка.отклонить(строка(данные))

    def test_позднее_совпадение_после_первого_отказа_не_принимается(проверка):
        проверка.отклонить(нативная_запись("чужое поручение") + нативная_запись())

    def test_первый_ответ_ассистента_закрывает_поиск(проверка):
        ответ = строка({"type": "response_item", "payload": {"type": "message", "role": "assistant", "content": []}})
        проверка.отклонить(ответ + нативная_запись())

    def test_пользовательская_имитация_не_доказывает_нативный_вызов(проверка):
        имитация = строка({"type": "response_item", "payload": {"type": "message", "role": "user", "content": [{"type": "input_text", "text": конверт()}]}})
        проверка.отклонить(имитация)


if __name__ == "__main__":
    unittest.main()

    def test_точный_максимальный_префикс_на_границах_и_юникод(сам):
        имя = сам.корень / 'Планирование/README.md'
        текст = сам.данные['файлы']['Планирование/README.md']
        ряд = next(с for с in текст.splitlines() if с.startswith('| Контекст |'))
        текст = текст.replace(ряд, '\n'.join(ряд.replace('Контекст', 'Цель «ё» ' + str(н)) for н in range(20)))
        имя.write_text(текст)
        новый = зафиксировать(сам.корень)
        полный = сам.собрать(коммит=новый)
        ожидаемый = copy.deepcopy(полный)
        число = 10
        ожидаемый['строки'] = полный['строки'][:число]
        ожидаемый['полнота'].update(выдача=False, показано=число,
            непоказано=len(полный['строки'])-число,
            непоказанные_строки=[с['идентификатор'] for с in полный['строки'][число:]])
        граница = len(сам.модуль.сериализовать(ожидаемый))
        сам.assertEqual(сам.собрать(коммит=новый, предел=граница), ожидаемый)
        сам.assertEqual(сам.собрать(коммит=новый, предел=граница+1), ожидаемый)
        меньше = сам.собрать(коммит=новый, предел=граница-1)
        сам.assertEqual(меньше['полнота']['показано'], 9)
        сам.assertLessEqual(len(сам.модуль.сериализовать(меньше)), граница-1)
        ожидаемый['строки'] = []
        ожидаемый['полнота'].update(показано=0, непоказано=len(полный['строки']),
            непоказанные_строки=[с['идентификатор'] for с in полный['строки']])
        сам.assertEqual(сам.собрать(коммит=новый, предел=len(сам.модуль.сериализовать(ожидаемый))), ожидаемый)


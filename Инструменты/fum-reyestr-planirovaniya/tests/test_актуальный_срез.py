    def test_акт_остаётся_назначением_без_запуска_и_приёмки(сам):
        имя = 'Планирование/акт.json'
        акт = {'схема': 'fum.поручение-дочерней-контрольной-точки.1',
            'координатор': '00000000-0000-0000-0000-000000000001',
            'исполнитель': '00000000-0000-0000-0000-000000000002',
            'ветка': 'refs/heads/codex/фикстура', 'область': ['Инструменты/фикстура.py'],
            'постановка': {'коммит': сам.коммит, 'путь': 'Планирование/цель.md', 'sha256': '0' * 64},
            'хэш_нативного_поручения': '1' * 64}
        (сам.корень / имя).write_text(json.dumps(акт))
        выбор = copy.deepcopy(сам.данные['выбор'])
        выбор['источники'].append({'вид': 'акт', 'путь': имя, 'шаг': 'FUM-STEP-0001',
                                   'наблюдение': '2026-10-04T01:00:00+03:00'})
        карточка = сам.карточка(сам.собрать(коммит=зафиксировать(сам.корень), выбор=выбор))
        событие = next(с for с in карточка['наблюдения'] if с['состояние'] == 'назначено')
        сам.assertEqual(событие['поручение'], акт)
        сам.assertFalse(событие['основание_проверено'])
        сам.assertIsNone(карточка['исполнитель'])
        сам.assertIsNone(карточка['подтверждение_состояния'])

    def test_команда_закреплённый_вывод_и_отказ_с_пустым_stdout(сам):
        выбор = сам.корень / 'выбор.json'
        выбор.write_text(json.dumps(сам.данные['выбор'], ensure_ascii=False))
        команда = [sys.executable, '-B', str(КОРЕНЬ / 'scripts/актуальный-срез.py'),
            '--корень-репозитория', str(сам.корень), '--коммит', сам.коммит,
            '--выбор', str(выбор), '--момент', сам.данные['момент'], '--предел-байтов', '65536', '--профиль']
        успех = subprocess.run(команда, capture_output=True)
        сам.assertEqual(успех.returncode, 0, успех.stderr)
        сам.assertEqual(успех.stdout, сам.модуль.сериализовать(сам.собрать()))
        сам.assertEqual(json.loads(успех.stderr)['объём_результата'], len(успех.stdout))
        команда[команда.index('--коммит')+1] = 'HEAD'
        отказ = subprocess.run(команда, capture_output=True)
        сам.assertEqual(отказ.returncode, 2)
        сам.assertEqual(отказ.stdout, b'')


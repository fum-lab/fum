    def test_поздняя_явная_отмена_не_стирает_историю(сам):
        путь = 'Планирование/наблюдение.json'
        запись = json.loads((сам.корень / путь).read_bytes())
        запись.update(состояние='снято', момент='2026-10-05T01:30:00+03:00',
            основание={'путь': 'Планирование/решение.md',
            'sha256': hashlib.sha256((сам.корень / 'Планирование/решение.md').read_bytes()).hexdigest(),
            'цитата': 'Снято FUM-STEP-0001.'})

КОРЕНЬ = Path(__file__).resolve().parents[1]
ФИКСТУРА = КОРЕНЬ / 'tests/фикстуры/актуальный-срез.json'


def загрузить_модуль():
    sys.path.insert(0, str(КОРЕНЬ / 'scripts'))
    import актуальный_срез
    return актуальный_срез


def гит(корень, *аргументы):
    return subprocess.check_output(['git', '-C', str(корень), *аргументы], stderr=subprocess.DEVNULL).decode().strip()


def подготовить_фикстуру(корень):
    данные = json.loads(ФИКСТУРА.read_bytes())
    гит(корень, 'init', '-q')
    гит(корень, 'config', 'user.name', 'Тест')
    гит(корень, 'config', 'user.email', 'test@example.invalid')
    for путь, текст in данные['файлы'].items():
        файл = корень / путь
        файл.parent.mkdir(parents=True, exist_ok=True)
        файл.write_text(текст, encoding='utf-8')
    return данные, зафиксировать(корень)


def зафиксировать(корень):
    гит(корень, 'add', '--all')
    гит(корень, 'commit', '-qm', 'Сохранить фикстуру')
    return гит(корень, 'rev-parse', 'HEAD')


class ТестАктуальногоСреза(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name).resolve()
        сам.данные, сам.коммит = подготовить_фикстуру(сам.корень)
        сам.модуль = загрузить_модуль()

    def собрать(сам, *, коммит=None, выбор=None, момент=None, предел=65536, срез=None, профиль=None):
        return сам.модуль.собрать_срез(
            срез or сам.модуль.СрезГит(сам.корень, коммит or сам.коммит),
            выбор or сам.данные['выбор'], момент or сам.данные['момент'], предел, профиль=профиль)

    def карточка(сам, результат):
        return next(строка for строка in результат['строки'] if строка['идентификатор'] == 'FUM-STEP-0001')

    def test_независимый_эталон_и_точное_происхождение(сам):
        результат = сам.собрать()
        эталон = сам.данные['эталон']
        карточка = сам.карточка(результат)
        сам.assertEqual(карточка['цель'], эталон['цель_карточки'])
        сам.assertIsNone(карточка['приоритет']['значение'])
        таблица = next(с for с in результат['строки'] if с['цель'] == эталон['цель_таблицы'])
        сам.assertEqual(таблица['приоритет']['значение'], эталон['приоритет'])
        сам.assertEqual(таблица['исполнитель'], эталон['исполнитель'])
        сам.assertIn(эталон['невошедшая_зависимость'], результат['полнота']['невошедшие_зависимости'])
        сам.assertFalse(результат['полнота']['весь_проект'])
        сам.assertTrue(результат['полнота']['выдача'])
        сам.assertEqual(результат['снимок']['коммит'], сам.коммит)
        for источник in результат['источники']:
            байты = (сам.корень / источник['путь']).read_bytes()
            сам.assertEqual(источник['sha256'], hashlib.sha256(байты).hexdigest())
            сам.assertEqual(источник['режим'], '100644')
        сам.assertIn(эталон['долгосрочная_цель'], [с['цель'] for с in результат['строки']])

    def test_повтор_и_грязный_рабочее_дерево_не_меняют_байты(сам):
        до = сам.модуль.сериализовать(сам.собрать())

    def test_старые_квитанции_читаются_без_переписывания_и_новых_полей(проверка):
        for с_поручением in (False, True):
            with проверка.subTest(с_поручением=с_поручением), открытый_вход() as (корень, источник, решение):
                коммит = обычный.хранилище.гит(корень, "rev-parse", "HEAD").strip()
                задача = "00000000-0000-0000-0000-000000000502"
                пара = {"model": "gpt-6-astra", "thinking": "low"}
                нативный(корень, источник, коммит, пара, задача=задача, поручение="Старое поручение" if с_поручением else None)
                первый = база.подтвердить_начало(корень, задача, коммит, источник, с_поручением=с_поручением)
                проверка.assertEqual("fum.начальная-база-задачи.2" if с_поручением else "fum.начальная-база-задачи.1", первый["схема"])

    def test_отложенные_строки_сохраняют_разные_пары_и_повтор(проверка):
        with пакет_фикстуры(2) as (корень, пакет):
            явный_пакет(пакет)
            исполнитель = отложенный.ИсполнительНазначений(корень, ЗАДАЧА)
            план, коммит = привязать_пакет(исполнитель, корень, пакет)
            with mock.patch.object(обычный, "проверить_инструменты"):
                for номер, (часть, пара) in enumerate(zip(пакет["назначения"], (ПАРА, ПРОИЗВОЛЬНАЯ)), 301):
                    направление = часть["направление"]

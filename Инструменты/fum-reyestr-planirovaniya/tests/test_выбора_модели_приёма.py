def явное_решение(решение, пара=ПАРА, *, обновление=False):
    решение["схема"] = "fum.решение-приёма.2"
    задача = решение["задача"]
    if обновление:
        задача.pop("projectId")
        задача.pop("title")
        задача.update(режим="обновить", threadId="00000000-0000-0000-0000-000000000999")
    задача.update(пара)
    return решение


def явный_пакет(пакет):
    пакет["схема"] = "fum.пакет-отложенных-назначений.2"
    for номер, назначение in enumerate(пакет["назначения"]):
        назначение["задача"].update((ПАРА, ПРОИЗВОЛЬНАЯ)[номер % 2])
    return пакет


def нативный(корень, источник, коммит, пара=ПАРА, *, задача=ЗАДАЧА, поручение=None):
    записи = [
        {"type": "session_meta", "payload": {"id": задача, "cwd": str(корень), "git": {"commit_hash": коммит}}},
        {"type": "turn_context", "payload": {"cwd": str(корень), "model": пара["model"], "effort": пара["thinking"]}},
    ]
    if поручение is not None:
        оболочка = "<codex_delegation>\n  <source_thread_id>" + ЗАДАЧА + "</source_thread_id>\n  <input>" + поручение + "</input>\n</codex_delegation>"
        записи.append({"type": "response_item", "payload": {"type": "function_call_output", "name": "create_thread", "output": оболочка}})
    источник.write_bytes(b"".join(строка(запись) for запись in записи))


def ранний_ребёнок(корень, коммит, допуск, пара, номер, *, явный=False):
    ребёнок = корень.parent / ("ребёнок-" + str(номер))
    задача = f"00000000-0000-0000-0000-{номер:012d}"
    обычный.хранилище.гит(корень, "worktree", "add", "-b", "codex/ребёнок-" + str(номер), str(ребёнок), коммит)
    источник = корень.parent / ("нативный-" + str(номер) + ".jsonl")
    нативный(ребёнок, источник, коммит, пара, задача=задача, поручение=допуск["аргументы"]["prompt"])
    база.подтвердить_начало(ребёнок, задача, коммит, источник, запрошенный_профиль=пара if явный else None)
    return ребёнок, задача, источник



    def test_неизвестное_не_даёт_доступную_программу(self):
        вариант = реестр.собрать(вход(), исходник(), "2026-09-11")["организации"][0]["варианты"][0]
        self.assertEqual(вариант["исход"], "условный")
        self.assertFalse(вариант["доступная_программа"])

    def test_положительная_метка_не_обходит_профиль_и_недоступные_условия(self):
        проверка = наблюдение()
        проверка.update({"допуск": "да", "неизвестно": []})
        self.assertFalse(реестр.оценить(проверка, "2026-09-11")["доступная_программа"])
        проверка["оформленный_заявитель"] = "не требуется"
        проверка["источники"].append({**проверка["источники"][0], "URL": "https://example.org/rules", "вид": "недоступно", "дата_чтения": None})
        self.assertFalse(реестр.оценить(проверка, "2026-09-11")["доступная_программа"])
        проверка["источники"].pop()
        проверка.update({"начало": None, "окончание": None, "тип_срока": "неизвестно"})
        self.assertFalse(реестр.оценить(проверка, "2026-09-11")["доступная_программа"])

    def test_прямое_подтверждение_обязательно_даже_при_положительной_оценке(self):
        данные = вход()
        проверка = данные["организации"][0]["варианты"][0]["проверки"][0]
        проверка.update({"допуск": "да", "неизвестно": []})
        проверка["источники"][0]["вид"] = "поисковый индекс"

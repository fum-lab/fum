    def test_истечение_и_устаревание_на_границах(self):
        проверка = наблюдение()
        проверка.update({"окончание": None, "допуск": "да", "неизвестно": [], "оформленный_заявитель": "не требуется", "тип_срока": "постоянный"})
        self.assertTrue(реестр.оценить(проверка, "2026-10-10")["доступная_программа"])
        self.assertEqual(реестр.оценить(проверка, "2026-10-11")["исход"], "требует уточнения")
        проверка["окончание"] = "2026-09-12"
        self.assertEqual(реестр.оценить(проверка, "2026-09-12")["исход"], "требует уточнения")
        self.assertEqual(реестр.оценить(проверка, "2026-09-13")["исход"], "недоступный")
        проверка["приём"] = "приостановлен"
        self.assertEqual(реестр.оценить(проверка, "2026-09-11")["исход"], "недоступный")


def ша(данные):
    return hashlib.sha256(данные).hexdigest()


def код_гита(корень, *аргументы):
    return subprocess.run(['git', *аргументы], cwd=корень, capture_output=True).returncode


def запись_проверки(запрос):
    return {'схема': 'fum.test-run.v4', 'идентификатор': '00000000-0000-0000-0000-000000000003',
            'порядок': 1, 'сессия': запрос, 'исполнитель': 'Открытая фикстура', 'вызов': 'git diff --check',
            'состояние': 'завершён', 'статус': 'неуспешно', 'код_завершения': 2,
            'длительность_наносекунды': 1000, 'пояснение': None, 'план': None, 'наблюдения': [],
            'отпечаток_содержимого': 'sha256:' + '1' * 64, 'переход_схемы': None,
            'профиль_проверки': {'идентификатор_отказа': None, 'класс': 'адресная',
                'ожидаемое_свидетельство': None, 'основание': None,
                'отпечаток_снимка': 'sha256:' + '2' * 64, 'полные_наборы': []}}


@contextmanager
def связанное_основание():
    with открытый_вход() as (корень, источник, решение):
        л = исполнение.хранилище.гит(корень, 'rev-parse', 'HEAD').strip()
        решение['основание'] += ' '
        исполнитель, результат, промежуточный, ветка = подготовленная_постановка(корень, источник, решение)
        запрос = результат['свидетельства']['команда']['путь']
        отказ = Path(запрос).parent / 'материалы/запуски-проверок/1_00000000-0000-0000-0000-000000000003.json'
        (корень / отказ).parent.mkdir(parents=True)
        (корень / отказ).write_text(json.dumps(запись_проверки(запрос), ensure_ascii=False, indent=2) + '\n')
        исполнение.хранилище.гит(корень, 'add', '.')
        исполнение.хранилище.гит(корень, 'commit', '-qm', 'C0 сохраняет известный неуспех')
        с0 = исполнение.хранилище.гит(корень, 'rev-parse', 'HEAD').strip()
        with mock.patch.object(исполнение, 'проверить_инструменты'):
            исполнитель.закрепить_постановку(результат['событие'], с0, ветка)
        новый = 'Журнал/2026-09-11_02-00-00_MSK_поправить-отображение/запрос.md'
        папка = (корень / новый).parent
        папка.mkdir(parents=True)
        (корень / новый).write_text('# Запрос\n\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: ' + ЗАДАЧА + '\n')
        (папка / 'отчёт.md').write_text('# Отчёт\n\n## Профиль времени выполнения\n\nОткрыто.\n')
        свидетельство = copy.deepcopy(результат['свидетельства']['основание'])
        поправка = {'схема': 'fum.поправка-отображения-основания.1', 'событие': результат['событие'],
                    'база': с0, 'ветка': ветка, 'роль': 'основание', 'свидетельство': свидетельство,
                    'после_sha256': ша(решение['основание'][:-1].encode()), 'запрос': новый,
                    'причина': 'Удалить только конечный ASCII-пробел производного основания.',
                    'исходный_отказ': {'путь': отказ.as_posix(), 'sha256': ша((корень / отказ).read_bytes()),
                        'идентификатор': '00000000-0000-0000-0000-000000000003', 'код': 2}}
        yield корень, источник, решение, исполнитель, л, с0, запрос, поправка


def выполнить(корень, поправка):
    модуль = importlib.import_module('отображение_основания')
    return модуль.поправить(корень, ЗАДАЧА, поправка)


class ПроверкаОтображенияОснования(unittest.TestCase):
    def test_суммарный_diff_сохраняет_C0_и_снимает_только_пробел(проверка):
        with связанное_основание() as (корень, источник, решение, исполнитель, л, с0, запрос, поправка):
            путь = корень / поправка['свидетельство']['путь']
            до = путь.read_bytes()
            состояние = исполнитель.хранилище.путь.read_bytes()
            исходный = json.loads(состояние)['данные']
            проверка.assertEqual(2, код_гита(корень, 'diff', '--check', л, с0))
            квитанция = выполнить(корень, поправка)
            после = до[:поправка['свидетельство']['конец'] - 1] + до[поправка['свидетельство']['конец']:]
            проверка.assertEqual(после, путь.read_bytes())
            проверка.assertEqual(квитанция, выполнить(корень, поправка))
            новое = json.loads(исполнитель.хранилище.путь.read_bytes())['данные']
            проверка.assertEqual(исходный['приёмы'], новое['приёмы'])
            проверка.assertEqual(исходный['попытки'], новое['попытки'])
            for ключ, значение in исходный['этапы'].items():
                проверка.assertEqual(значение, новое['этапы'][ключ])
            проверка.assertEqual(1, len(новое['этапы']) - len(исходный['этапы']))
            исполнение.хранилище.проверить_состояние(новое, исполнитель.хранилище.общий)
            проверка.assertEqual(до, исполнение.хранилище.гит(корень, 'cat-file', 'blob', с0 + ':' + поправка['свидетельство']['путь'], сырые=True))
            with проверка.assertRaisesRegex(исполнение.ОшибкаПриёма, 'Повтор изменил исходную пару'):
                исполнитель.подготовить(источник, ЗАДАЧА, решение, запрос, [])
            исполнение.хранилище.гит(корень, 'add', '.')
            исполнение.хранилище.гит(корень, 'commit', '-qm', 'C сохраняет адресную поправку')
            проверка.assertEqual(0, код_гита(корень, 'diff', '--check', л, 'HEAD'))
            проверка.assertEqual(2, json.loads((корень / поправка['исходный_отказ']['путь']).read_text())['код_завершения'])

    def test_иная_идентичность_либо_роль_отклоняется_до_эффекта(проверка):
        изменения = [lambda п: п.update(роль='команда'), lambda п: п.update(база='0' * 40),
            lambda п: п.update(ветка='refs/heads/codex/чужая'), lambda п: п.update(после_sha256='0' * 64),
            lambda п: п['свидетельство'].update(sha256='0' * 64),
            lambda п: п['свидетельство'].update(конец=п['свидетельство']['конец'] - 1),
            lambda п: п['свидетельство'].update(путь=п['запрос']),
            lambda п: п['исходный_отказ'].update(код=0)]
        for номер, изменить in enumerate(изменения):
            with проверка.subTest(номер=номер), связанное_основание() as (корень, источник, решение, исполнитель, л, с0, запрос, поправка):
                путь = корень / поправка['свидетельство']['путь']; до = путь.read_bytes()
                состояние = исполнитель.хранилище.путь.read_bytes()
                изменить(поправка)
                with проверка.assertRaises(ValueError):
                    выполнить(корень, поправка)
                проверка.assertEqual(до, путь.read_bytes())
                проверка.assertEqual(состояние, исполнитель.хранилище.путь.read_bytes())

    def test_изменённый_отчёт_не_нормализуется(проверка):
        for изменение in ('иной текст', 'после без собственной стадии'):
            with проверка.subTest(изменение=изменение), связанное_основание() as (корень, источник, решение, исполнитель, л, с0, запрос, поправка):
                путь = корень / поправка['свидетельство']['путь']; данные = путь.read_bytes()
                if изменение == 'иной текст':
                    данные += b'\n'
                else:
                    конец = поправка['свидетельство']['конец']; данные = данные[:конец - 1] + данные[конец:]
                путь.write_bytes(данные)
                with проверка.assertRaises(ValueError): выполнить(корень, поправка)
                проверка.assertEqual(данные, путь.read_bytes())

    def test_снимок_активность_и_возобновление_закрывают_поправку(проверка):
        for вид in ('снимок.json', 'возобновление.json', 'активный', 'закрытый маркер'):
            with проверка.subTest(вид=вид), связанное_основание() as (корень, источник, решение, исполнитель, л, с0, запрос, поправка):
                путь = корень / поправка['свидетельство']['путь']
                каталог = (корень / поправка['исходный_отказ']['путь']).parent
                if вид in ('снимок.json', 'возобновление.json'): (каталог / вид).write_text('{}')
                elif вид == 'закрытый маркер': путь.write_bytes(путь.read_bytes() + '\n<!-- FUM-CHECK-RUNS:BEGIN состояние=закрыт -->\n'.encode())
                else:
                    запись = запись_проверки(запрос); запись['состояние'] = 'выполняется'
                    for поле in ('статус', 'код_завершения', 'длительность_наносекунды', 'пояснение'): запись[поле] = None
                    (корень / поправка['исходный_отказ']['путь']).write_text(json.dumps(запись, ensure_ascii=False))
                до = путь.read_bytes()
                with проверка.assertRaises(ValueError): выполнить(корень, поправка)
                проверка.assertEqual(до, путь.read_bytes())

    def test_симлинк_и_hardlink_не_становятся_поправкой(проверка):
        for вид in ('симлинк', 'hardlink'):
            with проверка.subTest(вид=вид), связанное_основание() as (корень, источник, решение, исполнитель, л, с0, запрос, поправка):
                путь = корень / поправка['свидетельство']['путь']; сохранённый = корень.parent / 'отчёт.md'
                путь.rename(сохранённый)
                if вид == 'симлинк': путь.symlink_to(сохранённый)
                else: путь.hardlink_to(сохранённый)
                with проверка.assertRaises((ValueError, OSError)): выполнить(корень, поправка)
                проверка.assertTrue(сохранённый.read_bytes().endswith(b'\n'))

    def test_повтор_после_прерывания_завершает_одну_стадию(проверка):
        for граница in ('намерение', 'replace'):
            with проверка.subTest(граница=граница), связанное_основание() as (корень, источник, решение, исполнитель, л, с0, запрос, поправка):
                оригинал = исполнение.хранилище.установить
                путь = корень / поправка['свидетельство']['путь']
                def оборвать(цель, данные):
                    оригинал(цель, данные)
                    if (граница == 'replace' and цель == путь or граница == 'намерение' and цель == исполнитель.хранилище.путь):
                        raise OSError('Сохранённое прерывание')
                with mock.patch.object(исполнение.хранилище, 'установить', side_effect=оборвать), проверка.assertRaises(OSError):
                    выполнить(корень, поправка)
                квитанция = выполнить(корень, поправка)
                проверка.assertEqual(квитанция, выполнить(корень, поправка))
                поправка['причина'] += ' Другое намерение.'
                with проверка.assertRaises(ValueError): выполнить(корень, поправка)



"""Приватные квитанции вне любого Git-предка; одна активная доставка получателю."""
from contextlib import contextmanager
import fcntl
import os
from pathlib import Path

from приём_направления import безопасный_путь, требовать, установить, байты, хэш, разобрать, поля
from доставка_гит import выполнить


class Квитанции:
    def __init__(сам, каталог, идентификатор, корень):
        сам.каталог = Path(каталог)
        сам.идентификатор = идентификатор
        сам.корень = str(корень)

    @contextmanager
    def замок(сам):
        требовать(сам.каталог.is_absolute() and сам.каталог.resolve() == сам.каталог, "Нужен физический приватный каталог")
        безопасный_путь(сам.каталог, каталог=True)
        требовать(сам.каталог.parent.is_dir(), "Родитель приватного каталога должен существовать")
        for предок in (сам.каталог, *сам.каталог.parents):
            требовать(not (предок / ".git").exists(), "Приватное состояние находится под Git-предком")
            требовать(not ((предок / "objects").is_dir() and (предок / "HEAD").is_file()), "Приватное состояние находится в bare-репозитории")
        проверяемый = сам.каталог if сам.каталог.exists() else сам.каталог.parent
        требовать(выполнить(проверяемый, "rev-parse", "--git-dir", допустимые=(0, 128)).returncode != 0, "Состояние внутри Git")
        сам.каталог.mkdir(mode=0o700, exist_ok=True)
        сведения = сам.каталог.stat()
        требовать(сведения.st_uid == os.getuid() and сведения.st_mode & 0o077 == 0, "Каталог должен принадлежать владельцу и иметь права 0700")
        путь_замка = сам.каталог / "замок"
        безопасный_путь(путь_замка)
        дескриптор = os.open(путь_замка, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
        try:
            fcntl.flock(дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
            привязка = сам.каталог / "получатель.json"
            безопасный_путь(привязка)
            if привязка.exists():
                содержание = разобрать(привязка.read_bytes())
                поля(содержание, {"корень", "начато"})
                требовать(содержание["корень"] == сам.корень and type(содержание["начато"]) is bool, "Каталог другого получателя")
            else:
                требовать(not (сам.каталог / "активная.json").exists(), "Потеряна привязка каталога")
                установить(привязка, байты({"корень": сам.корень, "начато": False}))
            yield сам
        finally:
            os.close(дескриптор)

    def прочитать(сам):
        активная = сам.каталог / "активная.json"
        безопасный_путь(активная)
        if not активная.exists():
            требовать(разобрать((сам.каталог / "получатель.json").read_bytes())["начато"] is False, "Потерян начатый журнал доставки")
            требовать(not list(сам.каталог.glob("квитанция-*.json")), "Исчезла активная квитанция")
            return None
        ссылка = разобрать(активная.read_bytes())
        поля(ссылка, {"идентификатор"})
        требовать(isinstance(ссылка["идентификатор"], str) and len(ссылка["идентификатор"]) == 64
                  and all(буква in "0123456789abcdef" for буква in ссылка["идентификатор"]), "Повреждён адрес квитанции")
        путь = сам.каталог / ("квитанция-" + ссылка["идентификатор"] + ".json")
        безопасный_путь(путь)
        требовать(путь.exists(), "Потеряна квитанция; повторная инициализация запрещена")
        конверт = разобрать(путь.read_bytes())
        поля(конверт, {"данные", "sha256"})
        требовать(хэш(конверт["данные"]) == конверт["sha256"], "Повреждена квитанция")
        данные = конверт["данные"]
        требовать(данные["план"] == ссылка["идентификатор"], "Перепутана квитанция")
        if данные["план"] != сам.идентификатор:
            требовать(данные["получатель"] == "подтверждено" and данные["стадия"] in ("закоммичено", "содержание уже доставлено"), "Предыдущая доставка ещё не принята получателем")
            return None
        return данные

    def сохранить(сам, данные):
        поля(данные, {"схема", "план", "корень", "ref", "владелец", "источник", "до", "стадия", "дерево",
                      "защищённые", "проверка", "коммит", "публикация", "получатель", "основание"})
        требовать(данные["план"] == сам.идентификатор and данные["корень"] == сам.корень, "Чужая квитанция")
        # Адрес намерения пишется первым. Потеря следующей записи закрывает повтор.
        установить(сам.каталог / "получатель.json", байты({"корень": сам.корень, "начато": True}))
        установить(сам.каталог / "активная.json", байты({"идентификатор": сам.идентификатор}))
        установить(сам.каталог / ("квитанция-" + сам.идентификатор + ".json"), байты({"данные": данные, "sha256": хэш(данные)}))

#!/usr/bin/env python3
"""Конечный цикл координатора и владельца; stdout хранится приватно."""
import argparse
from pathlib import Path
import sys

from приём_направления import ОшибкаПриёма, байты, разобрать, безопасный_путь, поля
from обратная_доставка import Доставка
from доставка_план import построить_план, поручения, проверить_план


def прочитать(путь):
    безопасный_путь(Path(путь))
    return разобрать(Path(путь).read_bytes())


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    команды = разбор.add_subparsers(dest="действие", required=True)
    наблюдение = команды.add_parser("наблюдать", allow_abbrev=False)
    наблюдение.add_argument("--вход", required=True)
    для_координатора = команды.add_parser("поручения", allow_abbrev=False)
    для_координатора.add_argument("--план", required=True)
    для_координатора.add_argument("--владельцы", required=True)
    для_координатора.add_argument("--каталоги", required=True, help="Приватный JSON: физический корень получателя → его каталог квитанций")
    for имя in ("применить", "состояние", "проверить", "индекс", "коммит", "получение", "публикация"):
        команда = команды.add_parser(имя, allow_abbrev=False)
        команда.add_argument("--план", required=True)
        команда.add_argument("--корень", required=True)
        команда.add_argument("--задача", required=True)
        команда.add_argument("--владельцы", required=True)
        команда.add_argument("--каталог", required=True)
        if имя == "проверить":
            команда.add_argument("--тайм-аут", type=float, default=60)
            команда.add_argument("--запрос-проверки")
            команда.add_argument("--корневая-задача")
            команда.add_argument("команда", nargs=argparse.REMAINDER)
        if имя == "получение":
            команда.add_argument("--основание", required=True)
    аргументы = разбор.parse_args()
    try:
        if аргументы.действие == "наблюдать":
            вход = прочитать(аргументы.вход)
            поля(вход, {"источник", "получатели", "владельцы"})
            результат = построить_план(вход["источник"], вход["получатели"], прочитать(вход["владельцы"]))
        elif аргументы.действие == "поручения":
            план = проверить_план(прочитать(аргументы.план))
            каталоги = прочитать(аргументы.каталоги)
            результат = поручения(план)
            for поручение in результат:
                поручение["prompt"] += " План: " + str(Path(аргументы.план).resolve()) + "; реестр владельцев: " + str(Path(аргументы.владельцы).resolve()) + "; каталог квитанций: " + каталоги[поручение["корень"]] + "."
        else:
            доставка = Доставка(прочитать(аргументы.план), аргументы.корень, аргументы.задача, аргументы.владельцы, аргументы.каталог)
            if аргументы.действие == "проверить":
                команда = аргументы.команда[1:] if аргументы.команда[:1] == ["--"] else аргументы.команда
                результат = доставка.проверить(команда, аргументы.тайм_аут, запрос=аргументы.запрос_проверки,
                                               корневая_задача=аргументы.корневая_задача)
            elif аргументы.действие == "получение":
                результат = доставка.подтвердить_получение(аргументы.основание)
            else:
                метод = {"применить": доставка.применить, "состояние": доставка.состояние,
                         "коммит": доставка.подтвердить_коммит, "публикация": доставка.проверить_публикацию,
                         "индекс": доставка.подтвердить_индекс}[аргументы.действие]
                результат = метод()
        sys.stdout.buffer.write(байты(результат))
        if isinstance(результат, dict) and (результат.get("стадия") in ("конфликт", "эффект не подтверждён")
                                          or (аргументы.действие == "проверить" and результат.get("стадия") not in ("проверено", "ожидается индекс"))):
            return 3
        return 0
    except (ОшибкаПриёма, OSError, KeyError, TypeError, ValueError) as ошибка:
        sys.stderr.write("Обратная доставка остановлена: " + str(ошибка) + "\n")
        return 2


if __name__ == "__main__":
    raise SystemExit(главная())

"""Конечный выпуск явно подготовленных карточек СБОЙ и STEP.

Номера, содержание, статусы и число проявлений поступают извне.
План сохраняет точные before/after; применение не создаёт внешних задач.
"""
import argparse
import hashlib
import importlib
from pathlib import Path
import re
import sys
import tempfile
import tomllib
import unicodedata

import приём_направления as хранение
from приём_направления import ОшибкаПриёма, требовать
from вход_направления import добавить_строку_индекса

реестр = importlib.import_module("build-planning-registry")
ПОЛЯ = {"операция", "номер", "имя", "статус", "заголовок", "содержимое", "до_sha256"}
ЗАГОЛОВКИ_СБОЕВ = ["Идентификатор", "Статус", "Карточка", "Проявлений", "Основной шаг устранения"]
РАЗДЕЛЫ_СБОЯ = ("Наблюдаемый сбой", "Граница повторения", "Проявления", "Ожидание и классификация", "Механизм и системное устранение", "Связанные шаги", "Критерии закрытия", "Источники")


def хэш_текста(текст):
    return hashlib.sha256(текст.encode("utf-8")).hexdigest()


def прочитать(корень, имя):
    путь = Path(корень) / хранение.путь_результата(имя)
    хранение.безопасный_путь(путь)
    return путь.read_bytes().decode("utf-8") if путь.exists() else None


def разобрать_сбой(содержимое):
    начало = re.match(r"\A\+\+\+\r?\n(.*?)\r?\n\+\+\+(?:\r?\n|\Z)", содержимое, re.S)
    if начало is None:
        # Конечная совместимость с прежней шапкой; проза после первого H2 не задаёт ID.
        шапка = re.split(r"(?m)^## ", содержимое, maxsplit=1)[0]
        строки = шапка.splitlines()
        заголовки = [строка for строка in строки if строка.startswith("# ")]
        номера = [строка for строка in строки if строка.startswith("- Идентификатор:")]
        статусы = [строка for строка in строки if строка.startswith("- Статус:")]
        требовать(строки and len(заголовки) == len(номера) == len(статусы) == 1 and строки[0] == заголовки[0], "Нет однозначной исторической шапки сбоя")
        заголовок = re.fullmatch(r"# (FUM-СБОЙ-[0-9]{4}) — \S.*", заголовки[0])
        номер = re.fullmatch(r"- Идентификатор: `(FUM-СБОЙ-[0-9]{4})`\.", номера[0])
        статус = re.fullmatch(r"- Статус: `(активна|устранена|поглощена|снята)`(?:[ .].*)?", статусы[0])
        требовать(заголовок and номер and статус and заголовок[1] == номер[1], "Несогласованная историческая идентичность сбоя")
        return {"версия_схемы": 0, "идентификатор_сбоя": номер[1], "статус": статус[1]}
    try:
        метаданные = tomllib.loads(начало[1])
    except tomllib.TOMLDecodeError as ошибка:
        raise ОшибкаПриёма("Неверные метаданные сбоя") from ошибка
    хранение.поля(метаданные, {"версия_схемы", "идентификатор_сбоя", "статус"})
    требовать(type(метаданные["версия_схемы"]) is int and метаданные["версия_схемы"] == 1, "Неизвестная схема сбоя")
    return метаданные


def подготовить_карточку(запись, вид):
    хранение.поля(запись, ПОЛЯ | ({"проявлений", "основной_шаг"} if вид == "СБОЙ" else set()))
    номер = запись["номер"]
    требовать(type(номер) is str and re.fullmatch("FUM-" + вид + r"-[0-9]{4}", номер), "Неверный назначенный номер")
    требовать(type(запись["операция"]) is str and запись["операция"] in {"создать", "обновить"}, "Неизвестная операция")
    требовать(запись["до_sha256"] is None if запись["операция"] == "создать" else хранение.шестнадцатеричный(запись["до_sha256"]), "Нужен точный исходный хэш обновления")
    имя = запись["имя"]
    требовать(type(имя) is str and имя and all(часть and all(знак.isalnum() for знак in часть) for часть in имя.split("-")), "Нужен краткий slug без пути")
    заголовок = запись["заголовок"]
    требовать(хранение.текст(заголовок) and not any(знак in заголовок for знак in "[]|"), "Неверный заголовок")
    тело = запись["содержимое"]
    требовать(type(тело) is str and тело.strip() and "<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->" not in тело and not re.search(r"(?m)^#\s", тело), "Нужно готовое тело без H1")
    хранение.байты(тело)
    статус = запись["статус"]
    if вид == "СБОЙ":
        требовать(type(статус) is str and статус in {"активна", "устранена", "поглощена", "снята"}, "Неверный статус сбоя")
        требовать(type(запись["проявлений"]) is int and запись["проявлений"] > 0, "Нужно явно сверенное число проявлений")
        основной = запись["основной_шаг"]
        требовать(основной is None or type(основной) is str and re.fullmatch(r"FUM-STEP-[0-9]{4}", основной), "Неверный основной шаг")
        требовать(статус != "активна" or основной is not None, "Активному сбою нужен явный основной шаг")
        добавочный = {"устранена": "Подтверждение устранения", "поглощена": "Поглощение", "снята": "Причина снятия"}.get(статус)
        for раздел in РАЗДЕЛЫ_СБОЯ + ((добавочный,) if добавочный else ()):
            требовать(len(re.findall(r"(?m)^## " + re.escape(раздел) + r"\s*$", тело)) == 1, "Нужен единственный раздел: " + раздел)
            try:
                реестр.required_step_card_section(тело, раздел, номер)
            except ValueError as ошибка:
                raise ОшибкаПриёма(str(ошибка)) from ошибка
        путь = "Сбои/" + номер + "-" + имя + ".md"
        префикс = '+++\n"версия_схемы" = 1\n"идентификатор_сбоя" = "' + номер + '"\n"статус" = "' + статус + '"\n+++\n'
        строка = [номер, "`" + статус + "`", "[" + заголовок + "](" + Path(путь).name + ")", str(запись["проявлений"]), основной or "—"]
    else:
        требовать(type(статус) is str and статус in реестр.STEP_CARD_STATUSES, "Неверный статус шага")
        путь = "Планирование/карточки-шагов/" + реестр.STEP_CARD_EMOJI_BY_MACHINE[статус] + "-" + номер + "-" + имя + ".md"
        префикс = '+++\nschema_version = 1\ncard_id = "' + номер + '"\nstatus = "' + статус + '"\n+++\n'
        строка = [номер, реестр.INDEX_STATUS_BY_MACHINE[статус], "[" + заголовок + "](" + Path(путь).name + ")"]
    требовать(len(Path(путь).name.encode("utf-8")) <= 255, "Слишком длинное имя")
    содержимое = префикс + "# " + заголовок + "\n\n" + тело.strip() + "\n"
    if вид == "STEP":
        # Тот же парсер читает временный файл; checkout при планировании не пишется.
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный)
            файл = корень / путь
            файл.parent.mkdir(parents=True)
            файл.write_text(содержимое, encoding="utf-8")
            try:
                реестр.parse_step_card(файл, корень)
            except ValueError as ошибка:
                raise ОшибкаПриёма(str(ошибка)) from ошибка
    return путь, содержимое, строка


def изменить_индекс(содержимое, заголовки, строка, обновление):
    требовать(type(содержимое) is str, "Нет исходного индекса")
    строки = содержимое.splitlines(keepends=True)
    начала = [номер for номер, текст in enumerate(строки) if реестр.split_row(текст) == заголовки]
    требовать(len(начала) == 1, "Нет единственной таблицы индекса")
    начало = начала[0]
    конец = начало + 1
    while конец < len(строки) and строки[конец].startswith("|"):
        конец += 1
    ячейки = [реестр.split_row(текст) for текст in строки[начало:конец]]
    требовать(len(ячейки) >= 2 and реестр.is_separator(ячейки[1]) and all(len(ряд) == len(заголовки) for ряд in ячейки), "Повреждена таблица индекса")
    номера = [ряд[0] for ряд in ячейки[2:]]
    требовать(len(номера) == len(set(номера)), "Повтор номера в индексе")
    совпадения = [номер for номер, ряд in enumerate(ячейки[2:], 2) if ряд[0] == строка[0]]
    требовать(len(совпадения) == (1 if обновление else 0), "Индекс не соответствует операции")
    if not обновление and заголовки == реестр.STEP_CARD_INDEX_HEADERS:
        return добавить_строку_индекса(содержимое, строка)
    if обновление:
        ячейки[совпадения[0]] = строка
    else:
        ячейки.append(строка)
    ширины = [max(3, *(len(ряд[номер]) for ряд in ячейки)) for номер in range(len(заголовки))]
    ячейки[1] = ["-" * ширина for ширина in ширины]
    таблица = "".join("| " + " | ".join(значение.ljust(ширины[номер]) for номер, значение in enumerate(ряд)) + " |\n" for ряд in ячейки)
    return "".join(строки[:начало]) + таблица + "".join(строки[конец:])


def составить_файлы(пакет, исходное):
    хранение.проверить_структуру_данных(пакет)
    хранение.поля(пакет, {"схема", "сбои", "шаги"})
    требовать(пакет["схема"] == "fum.пакет-диагностики.1", "Неизвестная схема пакета")
    требовать(all(type(пакет[ключ]) is list for ключ in ("сбои", "шаги")) and 0 < len(пакет["сбои"]) + len(пакет["шаги"]) <= 100, "Нужен конечный непустой пакет")
    файлы, номера = {}, set()
    for ключ, вид, заголовки in (("сбои", "СБОЙ", ЗАГОЛОВКИ_СБОЕВ), ("шаги", "STEP", реестр.STEP_CARD_INDEX_HEADERS)):
        for запись in пакет[ключ]:
            путь, содержимое, строка = подготовить_карточку(запись, вид)
            требовать(запись["номер"] not in номера and путь not in файлы, "Повтор карточки в пакете")
            номера.add(запись["номер"])
            прежде = исходное(путь)
            обновление = запись["операция"] == "обновить"
            if обновление:
                требовать(type(прежде) is str and хэш_текста(прежде) == запись["до_sha256"], "Существующая карточка изменилась")
                прежний_номер = разобрать_сбой(прежде)["идентификатор_сбоя"] if вид == "СБОЙ" else реестр.split_step_card_frontmatter(прежде, путь)[0]["card_id"]
                требовать(прежний_номер == запись["номер"], "Обновление изменяет идентичность")
            else:
                требовать(прежде is None, "Создание перезаписывает существующий файл")
            файлы[путь] = {"до": прежде, "после": содержимое}
            индекс = str(Path(путь).parent / "README.md")
            if индекс not in файлы:
                исходный_индекс = исходное(индекс)
                файлы[индекс] = {"до": исходный_индекс, "после": исходный_индекс}
            файлы[индекс]["после"] = изменить_индекс(файлы[индекс]["после"], заголовки, строка, обновление)
    return файлы


def проверить_окружение(корень, файлы):
    for имя, изменение in файлы.items():
        путь = Path(корень) / имя
        ключ = unicodedata.normalize("NFC", путь.name).casefold()
        совпадения = [сосед.name for сосед in путь.parent.iterdir() if unicodedata.normalize("NFC", сосед.name).casefold() == ключ]
        требовать(совпадения in ([], [путь.name]), "Коллизия регистра либо Unicode")
        if путь.name != "README.md":
            номер = next(iter(хранение.идентичности_карточки(имя, изменение["после"])))
            for сосед in путь.parent.glob("*.md"):
                if сосед.name in {"README.md", путь.name}:
                    continue
                хранение.безопасный_путь(сосед)
                требовать(номер not in хранение.идентичности_карточки(str(Path(имя).parent / сосед.name), сосед.read_text(encoding="utf-8")), "Номер уже существует в другой карточке")


def подготовить(корень, задача, пакет):
    хранилище = хранение.Хранилище(корень, задача)
    владелец = хранилище._наблюдать_владельца()
    файлы = составить_файлы(пакет, lambda имя: прочитать(корень, имя))
    проверить_окружение(корень, файлы)
    требовать(хранилище._наблюдать_владельца() == владелец, "Владелец изменился при подготовке")
    данные = {"схема": "fum.план-пакета-диагностики.1", "задача": задача, "корень": str(хранилище.корень), "ref": владелец["ref"], "база": владелец["HEAD"], "пакет": пакет, "пакет_sha256": хранение.хэш(пакет), "файлы": файлы}
    return {"данные": данные, "sha256": хранение.хэш(данные)}


def применить(корень, задача, конверт):
    хранение.поля(конверт, {"данные", "sha256"})
    план = конверт["данные"]
    хранение.поля(план, {"схема", "задача", "корень", "ref", "база", "пакет", "пакет_sha256", "файлы"})
    требовать(конверт["sha256"] == хранение.хэш(план) and план["пакет_sha256"] == хранение.хэш(план["пакет"]), "Повреждён план")
    требовать(план["схема"] == "fum.план-пакета-диагностики.1" and план["задача"] == задача and план["корень"] == str(Path(корень).resolve()), "Чужой план")
    требовать(хранение.ветка_писателя(план["ref"]) and хранение.шестнадцатеричный(план["база"], 40), "Неверная база плана")
    требовать(type(план["файлы"]) is dict and план["файлы"], "Нет файлов плана")
    for изменение in план["файлы"].values():
        хранение.поля(изменение, {"до", "после"})
        требовать(изменение["до"] is None or type(изменение["до"]) is str, "Неверные исходные байты")
        требовать(type(изменение["после"]) is str, "Неверные новые байты")
    def исходное(имя):
        требовать(имя in план["файлы"], "Неполный план")
        return план["файлы"][имя]["до"]
    требовать(составить_файлы(план["пакет"], исходное) == план["файлы"], "План не соответствует пакету")
    хранилище = хранение.Хранилище(корень, задача)
    return хранилище.применить_файлы("пакет диагностики:" + конверт["sha256"], "карточки и индексы", {имя: запись["после"] for имя, запись in план["файлы"].items()}, ожидаемые_байты={имя: запись["до"] for имя, запись in план["файлы"].items()}, ожидаемая_ветка=план["ref"], ожидаемая_база=план["база"], проверить_окружение=lambda: проверить_окружение(корень, план["файлы"]))


def выполнить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("действие", choices=("план", "применить"))
    парсер.add_argument("--корень", type=Path, required=True)
    парсер.add_argument("--задача", required=True)
    парсер.add_argument("--вход", type=Path, required=True)
    параметры = парсер.parse_args()
    try:
        хранение.безопасный_путь(параметры.вход.absolute())
        данные = хранение.разобрать(параметры.вход.read_bytes())
        результат = подготовить(параметры.корень, параметры.задача, данные) if параметры.действие == "план" else применить(параметры.корень, параметры.задача, данные)
        sys.stdout.buffer.write(хранение.байты(результат))
        return 0
    except (ValueError, OSError) as ошибка:
        print(str(ошибка), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(выполнить())

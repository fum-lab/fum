def наблюдать_назначение(план, владельцы, *, порог_коммитов=None):
    """Повторное чтение назначения и Git. Не открывает и не изменяет квитанции."""
    проверить_план(план)
    требовать(порог_коммитов is None or (type(порог_коммитов) is int and порог_коммитов >= 1), "Порог — положительное число отсутствующих коммитов")
    назначение = план.get("назначение")
    источник = план["источник"]
    ошибка_входа = None
    try:
        сверить_реестр(владельцы, назначение)
        требовать(хэш(владельцы) == план["владельцы_sha256"], "Сдвинулся реестр владельцев")
        описание = {ключ: источник[ключ] for ключ in ("корень", "ref", "коммит", "владелец", "срез", "приёмка")}
        требовать(принять_источник(описание, назначение) == источник, "Изменился источник приёмки")
    except (ОшибкаПриёма, OSError, KeyError, TypeError, ValueError) as ошибка:
        ошибка_входа = str(ошибка)
    записи = []
    актуален = ошибка_входа is None
    for цель in план["получатели"]:
        запись = {ключ: цель[ключ] for ключ in ("корень", "ref", "владелец", "причина")}
        запись.update(коммит="unknown", отношение="unknown", отсутствующих_коммитов="unknown",
                      сигнал_недоставки="unknown", ожидание_секунд="unknown", порог_достигнут="unknown",
                      причина_ожидания=ошибка_входа or "unknown", снимок_плана_актуален=False,
                      рабочее_дерево="unknown", получатель="unknown", квитанция="не наблюдалась")
        if ошибка_входа is None:
            try:
                текущий = снимок(цель["корень"], цель["владелец"], цель["ref"], назначение)
                вид, _ = отношение(цель["корень"], источник["срез"], текущий["коммит"])
                число = int(гит(цель["корень"], "rev-list", "--count", текущий["коммит"] + ".." + источник["срез"]))
                состояние = "чисто"
                try:
                    требовать(not служебные_состояния(цель["корень"]), "Есть незавершённая Git-операция")
                    поддержанное_дерево(цель["корень"], источник["срез"])
                    чисто(цель["корень"])
                except ОшибкаПриёма as ошибка:
                    состояние = str(ошибка)
                требовать(текущий == снимок(цель["корень"], цель["владелец"], цель["ref"], назначение), "Получатель сдвинулся при наблюдении")
                требовать(снимок(источник["корень"], источник["владелец"], источник["ref"], назначение)["коммит"] == источник["коммит"], "Источник сдвинулся при наблюдении")
                запись.update(коммит=текущий["коммит"], отношение=вид, отсутствующих_коммитов=число,
                              сигнал_недоставки=вид not in ("в предках", "равное дерево"),
                              порог_достигнут=число >= порог_коммитов if порог_коммитов is not None else "unknown",
                              снимок_плана_актуален=all(текущий[ключ] == цель[ключ] for ключ in текущий),
                              рабочее_дерево=состояние,
                              причина_ожидания=(состояние if состояние != "чисто" else
                                  "Ожидается явная сверка и приём владельцем" if вид != "недоставленные коммиты" else
                                  "Принятый срез отсутствует в истории получателя"))
            except (ОшибкаПриёма, OSError, KeyError, TypeError, ValueError) as ошибка:
                запись["причина_ожидания"] = str(ошибка)
        актуален = актуален and запись["снимок_плана_актуален"]
        записи.append(запись)
    return {"схема": "fum.наблюдение-назначения-доставки.1", "план": план["идентификатор"],
            "назначение": назначение, "срез": источник["срез"], "источник_приёмки": источник["коммит"],
            "время_наблюдения": datetime.now(timezone.utc).isoformat(), "план_актуален": актуален,
            "порог_коммитов": порог_коммитов, "получатели": записи,
            "граница": "Снимок Git и заявленного назначения; доступность писателя, время начала ожидания, квитанции и получение не подтверждены"}

def объект(значение, поля):
    требовать(type(значение) is dict and set(значение) == set(поля), "Неверные поля решения приёма")


def содержательный(значение):
    return type(значение) is str and bool(значение.strip()) and "<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->" not in значение and "\x00" not in значение


def прочитать_вход(корень, источник, задача):
    try:
        снимок = обработка.получить_остаток(Path(источник), задача, корень_репозитория=Path(корень), без_записи=True)
        требовать(снимок["полнота_источника"] and снимок["непроверенный_хвост"] == 0, "Источник не полностью проверен")
        return снимок
    except (ValueError, OSError) as ошибка:
        raise ОшибкаПриёма("Нет достоверного полного первичного источника") from ошибка


def проверить_решение(корень, источник, задача, решение):
    объект(решение, {"схема", "экземпляр", "контекст", "история_sha256", "актуальность", "поздние", "основание", "ответ", "действие", "объём", "задача"})
    требовать(решение["схема"] == "fum.решение-приёма.1", "Неизвестная схема решения")
    требовать(решение["действие"] in {"новое", "обновить", "уточнить", "отклонить"}, "Неизвестное действие")
    требовать(решение["объём"] in {"планирование", "реализация", "описание"}, "Не задана граница предметной работы")
    требовать(решение["актуальность"] in {"актуально", "уточнено", "неясно", "отменено"}, "Неизвестная актуальность")
    требовать(содержательный(решение["ответ"]) and содержательный(решение["основание"]), "Нужны содержательные ответ и основание")
    требовать(type(решение["поздние"]) is list and len(set(решение["поздние"])) == len(решение["поздние"]), "Неверные поздние основания")
    try:
        обработка.проверить_контекст(решение["контекст"])
        обработка.отпечаток(решение["экземпляр"])
        обработка.отпечаток(решение["история_sha256"])
        снимок = прочитать_вход(корень, источник, задача)
        требовать(снимок["контекст"]["экземпляры"] == решение["контекст"]["экземпляры"], "Появился поздний ввод или пропущен исходный экземпляр")
        обработка.сверить_границы(Path(источник), [решение["контекст"]], без_записи=True)
        требовать(снимок["история_sha256"] == решение["история_sha256"], "Изменилась история обработки")
        исходное = обработка.сверить_экземпляры(решение, {**снимок, "граница": снимок["контекст"]["граница"]})
    except (ValueError, OSError) as ошибка:
        if isinstance(ошибка, ОшибкаПриёма):
            raise
        raise ОшибкаПриёма("Исходные свидетельства решения не подтверждены") from ошибка
    содержимое = исходное["содержимое"]
    требовать(type(содержимое) is list and содержимое and all(type(часть) is dict and set(часть) == {"type", "text"} and часть["type"] == "input_text" and type(часть["text"]) is str for часть in содержимое), "Для нетекстового источника нужен отдельный подтверждённый адаптер")
    команда = "".join(часть["text"] for часть in содержимое)
    требовать(содержательный(команда), "Пустая команда")
    if решение["актуальность"] in {"уточнено", "отменено"}:
        требовать(решение["поздние"], "Изменение смысла требует позднего источника")
    if решение["действие"] == "уточнить":
        требовать(решение["актуальность"] == "неясно", "Уточнение должно сохранять неясность")
    внешняя = решение["задача"]
    if внешняя is not None:
        требовать(решение["актуальность"] in {"актуально", "уточнено"} and решение["действие"] in {"новое", "обновить"}, "Неясный или отменённый вход не разрешает внешнюю задачу")
        требовать(type(внешняя) is dict and внешняя.get("режим") in {"создать", "обновить"}, "Неизвестный режим внешнего действия")
        поля = {"режим", "разрешение", "поручение"} | ({"projectId", "title"} if внешняя["режим"] == "создать" else {"threadId"})
        объект(внешняя, поля)
        требовать(type(внешняя["разрешение"]) is list and внешняя["разрешение"] and len(set(внешняя["разрешение"])) == len(внешняя["разрешение"]), "Нет явного свидетельства разрешения отдельной задачи")
        сообщения = {запись["экземпляр"]: запись for запись in снимок["сообщения"]}
        требовать(all(type(ссылка) is str and ссылка in сообщения and сообщения[ссылка]["происхождение"] == "человек" for ссылка in внешняя["разрешение"]), "Разрешение ссылается не на подтверждённого человека")
        требовать(содержательный(внешняя["поручение"]), "Пустое поручение")
        if внешняя["режим"] == "создать":
            требовать(текст(внешняя["projectId"]) and текст(внешняя["title"]), "Нужны наблюдённый проект и название")
        else:
            требовать(type(внешняя["threadId"]) is str and re.fullmatch(r"[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}", внешняя["threadId"]), "Нужен настоящий идентификатор задачи")
    return {"схема": "fum.проверенное-решение-приёма.1", "команда": команда, "решение": copy.deepcopy(решение), "источник": снимок["источник"], "контекст": снимок["контекст"]}


def заголовок_раздела(содержимое, название):
    маска = структура._link_tools().markdown_hidden_mask(содержимое)
    совпадения = [совпадение for совпадение in re.finditer(r"(?m)^## " + re.escape(название) + r"[ \t]*\r?$", содержимое) if not маска[совпадение.start()]]
    требовать(len(совпадения) == 1, "Неоднозначный или отсутствующий раздел: " + название)
    return совпадения[0]


def свидетельство(имя, содержимое, начало, часть, *, команда=False):
    данные = часть.encode("utf-8")
    смещение = len(содержимое[:начало].encode("utf-8"))
    результат = {"путь": имя, "начало": смещение, "конец": смещение + len(данные), "sha256": hashlib.sha256(данные).hexdigest()}
    if команда:
        результат["формат"] = "текст"
    return результат


def подготовить_пару(корень, запрос, задача, событие, команда, ответ, основание):
    """План добавления в собственный открытый Журнал без записи или обработки0177."""
    требовать(type(запрос) is str and re.fullmatch(r"Журнал/[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}-[0-9]{2}-[0-9]{2}_MSK_[^/]+/запрос\.md", запрос), "Нужен точный запрос своей рабочей сессии")
    требовать(type(событие) is str and re.fullmatch(r"[0-9a-f]{64}", событие), "Нужна идентичность исходного сообщения")
    требовать(all(содержательный(часть) for часть in (команда, ответ, основание)), "Пара команды и ответа пуста")
    путь = обработка.локальный_путь(Path(корень), запрос)
    имя_отчёта = str(Path(запрос).with_name("отчёт.md"))
    исходный_запрос = обработка.прочитать_файл(путь).decode("utf-8")
    исходный_отчёт = обработка.прочитать_файл(обработка.локальный_путь(Path(корень), имя_отчёта)).decode("utf-8")
    граница = заголовок_раздела(исходный_запрос, "Идентификатор сеанса Codex")
    после = исходный_запрос[граница.end():]
    тело = re.split(r"(?m)^## ", после, maxsplit=1)[0].strip()
    требовать(тело == "Codex-Thread-ID: " + задача, "Чужой владелец Журнала")
    требовать("состояние=закрыт" not in исходный_отчёт, "Закрытый отчёт не возобновляется")
    ограда = структура._fence_for(команда)
    маркер = "<!-- FUM-INTAKE: " + событие + " -->"
    начало_команды = маркер + "\n\n" + ограда + "text\n"
    блок_команды = начало_команды + команда + "\n" + ограда + "\n\n"
    начало_ответа = маркер + "\n\nОтвет: "
    перед_основанием = начало_ответа + ответ + "\n\nОснование: "
    блок_ответа = перед_основанием + основание + "\n\n"
    уже = маркер in исходный_запрос or маркер in исходный_отчёт
    if уже:
        требовать(исходный_запрос.count(маркер) == исходный_отчёт.count(маркер) == 1 and блок_команды in исходный_запрос and блок_ответа in исходный_отчёт, "Повтор изменил исходную пару или сохранил её частично")
        новый_запрос, новый_отчёт = исходный_запрос, исходный_отчёт
    else:
        заголовок_раздела(исходный_запрос, "Текст запроса")
        новый_запрос = исходный_запрос[:граница.start()] + блок_команды + исходный_запрос[граница.start():]
        профиль = заголовок_раздела(исходный_отчёт, "Профиль времени выполнения")
        новый_отчёт = исходный_отчёт[:профиль.start()] + блок_ответа + исходный_отчёт[профиль.start():]
    начало_в_запросе = новый_запрос.index(блок_команды) + len(начало_команды)
    начало_в_отчёте = новый_отчёт.index(блок_ответа)
    свидетельства = {
        "команда": свидетельство(запрос, новый_запрос, начало_в_запросе, команда, команда=True),
        "ответ": свидетельство(имя_отчёта, новый_отчёт, начало_в_отчёте + len(начало_ответа), ответ),
        "основание": свидетельство(имя_отчёта, новый_отчёт, начало_в_отчёте + len(перед_основанием), основание)}
    return ({} if уже else {запрос: новый_запрос, имя_отчёта: новый_отчёт}), свидетельства


def добавить_строку_индекса(содержимое, строка):
    строки = содержимое.splitlines(keepends=True)
    начало = [номер for номер, значение in enumerate(строки) if [ячейка.strip() for ячейка in значение.strip().strip("|").split("|")] == ["Идентификатор", "Статус", "Карточка"]]
    требовать(len(начало) == 1, "Неоднозначная таблица карточек")
    начало = начало[0]
    конец = начало + 1
    while конец < len(строки) and строки[конец].startswith("|"):
        конец += 1
    ячейки = [[ячейка.strip() for ячейка in значение.strip().strip("|").split("|")] for значение in строки[начало:конец]]
    требовать(len(ячейки) >= 2 and all(len(ряд) == 3 for ряд in ячейки), "Повреждена таблица карточек")
    требовать(all(ряд[0] != строка[0] for ряд in ячейки[2:]), "Номер уже присутствует в индексе")
    ячейки.append(строка)
    ширины = [max(len(ряд[номер]) for ряд in ячейки) for номер in range(3)]
    ячейки[1] = ["-" * ширина for ширина in ширины]
    таблица = "".join("| " + " | ".join(значение.ljust(ширины[номер]) for номер, значение in enumerate(ряд)) + " |\n" for ряд in ячейки)
    return "".join(строки[:начало]) + таблица + "".join(строки[конец:])


def идентичность_карточки(содержимое, тип):
    выражение = r'(?m)^card_id = "(FUM-STEP-[0-9]{4})"$' if тип == "шаг" else r"<!-- FUM-REQUIREMENT-ID: (FUM-REQ-[0-9]{4}) -->"
    совпадения = re.findall(выражение, содержимое)
    требовать(len(совпадения) == 1, "Неоднозначная идентичность карточки")
    return совпадения[0]


def подготовить_карточки(корень, карточки, номера, запрос):
    """Модель задаёт содержание, механизм назначает ID, путь и индекс."""
    требовать(type(карточки) is list, "Нужен конечный список карточек")
    файлы = {}
    созданные = set()
    for карточка in карточки:
        требовать(type(карточка) is dict and карточка.get("тип") in {"шаг", "требование"} and карточка.get("операция") in {"создать", "обновить"}, "Неизвестная операция карточки")
        тип = карточка["тип"]
        каталог = "Планирование/карточки-шагов" if тип == "шаг" else "Требования"
        требовать(содержательный(карточка.get("содержимое")), "Пустое содержание карточки")
        if карточка["операция"] == "обновить":
            объект(карточка, {"тип", "операция", "путь", "ожидаемый_sha256", "содержимое"})
            имя = карточка["путь"]
            требовать(type(имя) is str and Path(имя).parent.as_posix() == каталог and Path(имя).name != "README.md" and имя.endswith(".md"), "Обновление вне каталога карточек")
            путь = обработка.локальный_путь(Path(корень), имя)
            прежде = обработка.прочитать_файл(путь)
            требовать(hashlib.sha256(прежде).hexdigest() == карточка["ожидаемый_sha256"], "Карточка изменилась после рассмотрения")
            требовать(идентичность_карточки(прежде.decode("utf-8"), тип) == идентичность_карточки(карточка["содержимое"], тип), "Обновление изменяет неизменяемый номер")
            требовать(имя not in файлы, "Повтор карточки в плане")
            файлы[имя] = карточка["содержимое"]
            continue
        объект(карточка, {"тип", "операция", "имя", "заголовок", "содержимое"})
        семейство = "FUM-STEP" if тип == "шаг" else "FUM-REQ"
        номер = номера.get(семейство)
        требовать(type(номер) is str and re.fullmatch(re.escape(семейство) + r"-[0-9]{4}", номер) and семейство not in созданные, "Нет единственного зарезервированного номера")
        созданные.add(семейство)
        метка = карточка["имя"]
        заголовок = карточка["заголовок"]
        требовать(type(метка) is str and re.fullmatch(r"[А-Яа-яЁёA-Za-z0-9]+(?:-[А-Яа-яЁёA-Za-z0-9]+)*", метка), "Неверное имя карточки")
        требовать(текст(заголовок) and not any(знак in заголовок for знак in "[]|"), "Неверный заголовок карточки")
        имя = каталог + "/🟡-" + (номер + "-" if тип == "шаг" else "") + метка + ".md"
        требовать(len(Path(имя).name.encode("utf-8")) <= 255, "Слишком длинное имя карточки")
        путь = обработка.локальный_путь(Path(корень), имя)
        совпадения = [существующий for существующий in os.listdir(путь.parent) if unicodedata.normalize("NFC", существующий).casefold() == unicodedata.normalize("NFC", путь.name).casefold()]
        требовать(not совпадения and имя not in файлы, "Карточка уже существует")
        тело = карточка["содержимое"].strip() + "\n"
        требовать(not re.search(r"(?m)^# ", тело) and "FUM-REQUIREMENT-ID:" not in тело and not re.search(r"(?m)^card_id\s*=", тело), "Модельное тело не назначает собственный ID или второй заголовок")
        if тип == "шаг":
            префикс = '+++\nschema_version = 1\ncard_id = "' + номер + '"\nstatus = "active"\n+++\n# ' + заголовок + "\n\n"
            источники = "\n## Источники\n\n- [Исходная команда](../../" + запрос + ")\n"
        else:
            префикс = "# " + заголовок + "\n\n<!-- FUM-REQUIREMENT-ID: " + номер + " -->\n\n"
            источники = "\n## Источники требований\n\n- [Исходная команда](../" + запрос + ")\n"
        требовать(not re.search(r"(?m)^## Источники(?: требований)?\s*$", тело), "Источники карточки формирует исполнитель")
        файлы[имя] = префикс + тело + источники
        индекс = каталог + "/README.md"
        содержимое_индекса = файлы.get(индекс)
        if содержимое_индекса is None:
            содержимое_индекса = обработка.прочитать_файл(обработка.локальный_путь(Path(корень), индекс)).decode("utf-8")
        if тип == "шаг":
            файлы[индекс] = добавить_строку_индекса(содержимое_индекса, [номер, "🟡 Актуально", "[" + заголовок + "](" + Path(имя).name + ")"])
        else:
            требовать(номер not in содержимое_индекса, "Номер требования уже индексирован")
            блок = "\n## Принятые направления\n\n- `" + номер + "` — [🟡 " + заголовок + "](" + Path(имя).name + ")\n"
            конец = содержимое_индекса.find("<!-- FUM-MD-RECENCY:BEGIN -->")
            конец = len(содержимое_индекса) if конец < 0 else конец
            файлы[индекс] = содержимое_индекса[:конец].rstrip() + "\n" + блок + "\n" + содержимое_индекса[конец:]
    return файлы

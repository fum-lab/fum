def проверить_инструменты(корень, коммит):
    """Одноразовый CLI исполняет принятый код своего checkout без подмены после импорта."""
    требовать(Path(корень).resolve() == КОРЕНЬ_КОДА, "Исполнитель загружен из другого checkout")
    хранилище.гит(корень, "diff", "--exit-code", коммит, "--", "Инструменты")
    требовать(not хранилище.гит(корень, "ls-files", "--others", "--exclude-standard", "--", "Инструменты").strip(), "Новый исполняемый код ещё не сохранён в коммите постановки")
    for путь, отпечаток in ЗАГРУЖЕННЫЙ_КОД.items():
        хранилище.безопасный_путь(путь)
        требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == отпечаток, "Код изменён после импорта")


def событие_источника(задача, экземпляр):
    return хранилище.хэш({"задача": задача, "экземпляр": экземпляр})


def смысл_решения(решение):
    return {ключ: значение for ключ, значение in решение.items() if ключ not in {"контекст", "история_sha256"}}


def проверить_планирование(корень):
    модуль = runpy.run_path(str(Path(__file__).with_name("build-planning-registry.py")))
    реестр = модуль["build_registry"](Path(корень))
    ошибки = модуль["validate_registry_object"](реестр)
    требовать(not ошибки, "Плановый реестр отклонил локальный результат: " + "; ".join(ошибки))
    return модуль["registry_json"](реестр)


def без_свежести(содержимое):
    return re.sub(r"\n*<!-- FUM-MD-RECENCY:BEGIN -->\n.*?<!-- FUM-MD-RECENCY:END -->\n?\Z", "", содержимое, flags=re.S).rstrip()


def проверить_исправление(исправление):
    вход.объект(исправление, {"схема", "событие", "ожидаемый_план_sha256", "база", "ветка", "причина", "файлы"})
    требовать(исправление["схема"] == "fum.исправление-плана-приёма.1", "Неизвестная схема исправления")
    требовать(хранилище.шестнадцатеричный(исправление["событие"]) and хранилище.шестнадцатеричный(исправление["ожидаемый_план_sha256"]), "Неверная идентичность исправления")
    требовать(хранилище.шестнадцатеричный(исправление["база"], 40) and хранилище.ветка_писателя(исправление["ветка"]), "Неверная база исправления")
    требовать(вход.содержательный(исправление["причина"]), "Нужна причина исправления")
    требовать(type(исправление["файлы"]) is list and исправление["файлы"], "Нет карточек исправления")
    имена = set()
    for изменение in исправление["файлы"]:
        вход.объект(изменение, {"путь", "ожидаемый_sha256", "содержимое"})
        имя = изменение["путь"]
        хранилище.путь_результата(имя)
        требовать(Path(имя).parent.as_posix() in {"Требования", "Планирование/карточки-шагов"} and Path(имя).name != "README.md" and имя.endswith(".md"), "Исправление допускает только карточки исходного плана")
        требовать(имя not in имена and хранилище.шестнадцатеричный(изменение["ожидаемый_sha256"]) and вход.содержательный(изменение["содержимое"]), "Повтор либо повреждённое исправление карточки")
        имена.add(имя)
    хранилище.байты(исправление)


def добавлен_пропущенный_статус(имя, до, после):
    """Только одна явная строка прежнего статуса; исходные байты не исправляются."""
    раздел = "## Статус и границы\n\n"
    содержание = без_свежести(до)
    if re.search(r"(?m)^ {0,3}(?:-+|=+)[ \t]*\r?$", содержание):
        return False
    заголовки = [вход.реестр.clean_text(совпадение.group(1)) for совпадение in re.finditer(r"(?m)^##\s+(.+?)\s*$", содержание)]
    if содержание.count(раздел) != 1 or заголовки.count("Статус и границы") != 1:
        return False
    открытый = вход.реестр.REQUIREMENT_ID_RE.sub("", содержание)
    if "<" in открытый or "-->" in открытый or re.search(r"(?m)^ {0,3}(?:`{3,}|~{3,})", открытый):
        return False
    прежнее = вход.реестр.section_body(до, "Статус и границы")
    if not прежнее or re.search(r"статус|—\s*`", прежнее, re.I) or any(символ in прежнее for символ in вход.реестр.REQUIREMENT_STATUSES):
        return False
    символы = [символ for символ in вход.реестр.REQUIREMENT_STATUSES if Path(имя).name.startswith(символ + "-")]
    if len(символы) != 1:
        return False
    вставка = "Статус требования — `" + символы[0] + "`.\n\n"
    return после == до.replace(раздел, раздел + вставка, 1)


def проверить_границы_карточки(имя, до, после):
    тип = "требование" if имя.startswith("Требования/") else "шаг"
    требовать(вход.идентичность_карточки(до, тип) == вход.идентичность_карточки(после, тип), "Исправление меняет идентичность карточки")
    заголовки = [re.findall(r"(?m)^ {0,3}#[ \t]+[^\r\n]+", текст) for текст in (до, после)]
    требовать(len(заголовки[0]) == 1 and заголовки[0] == заголовки[1], "Исправление меняет заголовок карточки")
    требовать(re.findall(r"(?m)^[^\r\n]+\r?\n {0,3}=+[ \t]*$", до) == re.findall(r"(?m)^[^\r\n]+\r?\n {0,3}=+[ \t]*$", после), "Исправление добавляет заголовок подчёркиванием")
    if тип == "требование":
        шапки = []
        for содержимое in (до, после):
            _, конец = вход.реестр.first_level_one_heading(содержимое, имя)
            маркер = re.match(r"\s*" + вход.реестр.REQUIREMENT_ID_RE.pattern, содержимое[конец:])
            требовать(маркер is not None, "Скрыт маркер требования")
            шапки.append(содержимое[:конец + маркер.end()])
        требовать(шапки[0] == шапки[1], "Исправление меняет шапку либо скрывает идентичность")
        требовать(вход.реестр.section_body(до, "Статус и границы") == вход.реестр.section_body(после, "Статус и границы")
                  or добавлен_пропущенный_статус(имя, до, после), "Исправление меняет статус и границы")
    else:
        прежнее, _ = вход.реестр.split_step_card_frontmatter(до, имя)
        новое, _ = вход.реестр.split_step_card_frontmatter(после, имя)
        требовать(хранилище.байты(прежнее) == хранилище.байты(новое), "Исправление меняет статус или метаданные шага")


def эффективные_файлы(запись):
    результат = dict(запись["файлы"])
    if "исправление" in запись:
        результат.update({изменение["путь"]: изменение["содержимое"] for изменение in запись["исправление"]["намерение"]["файлы"]})
    return результат


def проверить_запись(запись):
    поля = {"схема", "задача", "корень", "ref", "база", "источник", "экземпляр", "решение", "запрос", "карточки", "номера", "файлы", "свидетельства", "реестр", "готов", "постановка", "наблюдение"}
    требовать(type(запись) is dict and запись.get("схема") in {"fum.исполнение-приёма.1", "fum.исполнение-приёма.2"}, "Неизвестная схема сохранённого приёма")
    вход.объект(запись, поля | ({"исправление"} if запись["схема"] == "fum.исполнение-приёма.2" else set()))
    требовать(хранилище.идентификатор_задачи(запись["задача"]) and хранилище.идентификатор_задачи(запись["источник"]), "Неверные владельцы приёма")
    требовать(хранилище.абсолютный_корень(запись["корень"]) and хранилище.ветка_писателя(запись["ref"]) and хранилище.шестнадцатеричный(запись["база"], 40), "Неверная база приёма")
    требовать(хранилище.шестнадцатеричный(запись["экземпляр"]) and type(запись["готов"]) is bool, "Неверная идентичность либо готовность приёма")
    требовать(type(запись["решение"]) is dict and type(запись["карточки"]) is list and type(запись["номера"]) is dict, "Неверное решение приёма")
    требовать(type(запись["файлы"]) is dict and запись["файлы"] and all(type(значение) is str for значение in запись["файлы"].values()), "Нет точного плана приёма")
    for имя in запись["файлы"]:
        хранилище.путь_результата(имя)
    вход.объект(запись["свидетельства"], {"команда", "ответ", "основание"})
    for имя, свидетельство in запись["свидетельства"].items():
        try:
            вход.обработка.проверить_свидетельство(свидетельство, команда=имя == "команда")
        except ValueError as ошибка:
            raise ОшибкаПриёма("Повреждено свидетельство приёма") from ошибка
        требовать(свидетельство["путь"] in запись["файлы"], "Свидетельство вне сохранённого плана")
    требовать(запись["постановка"] is None or type(запись["постановка"]) is dict, "Неверная постановка приёма")
    требовать(запись["реестр"] is None or type(запись["реестр"]) is str and запись["реестр"].strip(), "Неверный снимок машинного реестра")
    требовать(not запись["готов"] or запись["реестр"] is not None, "Готовность без машинного реестра")
    требовать(запись["наблюдение"] is None or type(запись["наблюдение"]) is dict, "Неверное наблюдение задачи")
    if "исправление" in запись:
        квитанция = запись["исправление"]
        вход.объект(квитанция, {"намерение", "sha256", "исходный_отказ", "реестр_до"})
        исправление = квитанция["намерение"]
        проверить_исправление(исправление)
        требовать(квитанция["sha256"] == хранилище.хэш(исправление) and вход.содержательный(квитанция["исходный_отказ"]), "Повреждена квитанция исправления")
        требовать(квитанция["реестр_до"] is None or type(квитанция["реестр_до"]) is str, "Повреждены исходные байты реестра")
        требовать(исправление["событие"] == событие_источника(запись["источник"], запись["экземпляр"]) and исправление["ветка"] == запись["ref"] and исправление["ожидаемый_план_sha256"] == хранилище.хэш(запись["файлы"]), "Исправление не связано с исходным планом")
        for изменение in исправление["файлы"]:
            имя = изменение["путь"]
            требовать(имя in запись["файлы"] and hashlib.sha256(запись["файлы"][имя].encode()).hexdigest() == изменение["ожидаемый_sha256"], "Исправление изменяет исходный набор карточек")
            проверить_границы_карточки(имя, запись["файлы"][имя], изменение["содержимое"])


def сверить_журнал_коммита(запись, имя, данные):
    содержимое = данные.decode("utf-8")
    команда = имя == запись["запрос"]
    если_запрос = "Текст запроса" if команда else "Профиль времени выполнения"
    граница = вход.заголовок_раздела(содержимое, если_запрос)
    if команда:
        владелец = вход.заголовок_раздела(содержимое, "Идентификатор сеанса Codex")
        конец = вход.конец_раздела(содержимое, владелец)
        требовать(содержимое[владелец.end():конец].strip() == "Codex-Thread-ID: " + запись["задача"], "Коммит содержит чужой Журнал")
    маркер = "<!-- FUM-INTAKE: " + запись["экземпляр"] + " -->"
    исходное = запись["файлы"][имя]
    исходная_граница = вход.заголовок_раздела(исходное, если_запрос)
    конец_блока = вход.конец_раздела(исходное, исходная_граница) if команда else исходная_граница.start()
    блок = исходное[исходное.index(маркер):конец_блока]
    требовать(содержимое.count(маркер) == 1 and блок in содержимое, "В коммите изменён каркас пары Журнала")
    позиция = содержимое.index(блок)
    предел = вход.конец_раздела(содержимое, граница) if команда else граница.start()
    требовать(позиция + len(блок) <= предел and (not команда or позиция >= граница.end()), "В коммите пара перемещена за пределы своего раздела")
    маска = вход.структура._link_tools().markdown_hidden_mask(содержимое)
    требовать(not маска[позиция + len(маркер)], "В коммите пара скрыта внутри ограждённого блока")
    for свидетельство in запись["свидетельства"].values():
        if свидетельство["путь"] == имя:
            try:
                вход.обработка.фрагмент(свидетельство, данные)
            except ValueError as ошибка:
                raise ОшибкаПриёма("Коммит не содержит принятую пару Журнала") from ошибка


class ИсполнительПриёма:
    def __init__(сам, корень, задача):
        сам.хранилище = хранилище.Хранилище(корень, задача)
        сам.корень = сам.хранилище.корень
        сам.задача = задача

    def _прочитать(сам, состояние, событие):
        запись = состояние["приёмы"].get(событие)
        требовать(запись is not None, "Нет сохранённой местной стадии приёма")
        проверить_запись(запись)
        требовать(событие == событие_источника(запись["источник"], запись["экземпляр"]), "Событие не соответствует источнику")
        требовать(запись["задача"] == сам.задача and запись["корень"] == str(сам.корень), "Другой владелец приёма")
        владелец = сам.хранилище.проверить_владельца_под_замком(состояние)
        требовать(владелец["ref"] == запись["ref"], "Изменилась ветка приёма")
        return запись

    def _сверить_местное(сам, запись, проверенное):
        пустой, свидетельства = вход.подготовить_пару(сам.корень, запись["запрос"], сам.задача, запись["экземпляр"], проверенное["команда"], запись["решение"]["ответ"], запись["решение"]["основание"])
        требовать(not пустой, "Утрачена ранее сохранённая пара Журнала")
        требовать(свидетельства == запись["свидетельства"], "Изменились точные диапазоны пары Журнала")
        сам._сверить_карточки(запись)

    def _сверить_карточки(сам, запись):
        for имя, ожидаемое in эффективные_файлы(запись).items():
            if имя.startswith("Журнал/"):
                continue
            путь = вход.обработка.локальный_путь(сам.корень, имя)
            фактическое = вход.обработка.прочитать_файл(путь).decode("utf-8")
            требовать(без_свежести(фактическое) == без_свежести(ожидаемое), "Изменён принятый плановый результат: " + имя)

    def подготовить(сам, источник, исходная_задача, решение, запрос, карточки, *, номера=None):
        проверенное = вход.проверить_решение(сам.корень, источник, исходная_задача, решение)
        событие = событие_источника(исходная_задача, решение["экземпляр"])
        смысл = смысл_решения(решение)
        сам.хранилище.занять()
        with сам.хранилище.изменить() as состояние:
            прежняя = состояние["приёмы"].get(событие)
            if прежняя is not None:
                запись = сам._прочитать(состояние, событие)
                требовать("исправление" not in запись or запись["готов"], "Незавершённое исправление: повторите исправить-план с тем же JSON")
                требовать(хранилище.байты(запись["решение"]) == хранилище.байты(смысл) and хранилище.байты(запись["карточки"]) == хранилище.байты(карточки) and запись["запрос"] == запрос, "Повтор изменил принятую операцию")
                требовать(номера is None or запись["номера"] == номера, "Повтор изменил назначенные номера")
                запись = copy.deepcopy(запись)
            else:
                запись = None
        if запись is None:
            требовать(type(карточки) is list, "Нужен конечный список карточек")
            виды = [{"шаг": "FUM-STEP", "требование": "FUM-REQ"}.get(карточка.get("тип")) for карточка in карточки if type(карточка) is dict and карточка.get("операция") == "создать"]
            требовать(len(set(виды)) == len(виды) and None not in виды, "Один новый номер каждого вида на приём")
            требовать(решение["действие"] != "новое" or карточки, "Новое направление требует карточки постановки")
            основание = "Источник " + исходная_задача + "; экземпляр " + решение["экземпляр"]
            if виды:
                if номера is None:
                    номера = сам.хранилище.выделить(событие, виды, основание)
                else:
                    требовать(set(номера) == set(виды), "Резерв не соответствует новым карточкам")
                    номера = сам.хранилище.резервировать(событие, номера, основание)
            else:
                требовать(номера in (None, {}), "Нет карточек для резерва")
                номера = {}
            файлы, свидетельства = вход.подготовить_пару(сам.корень, запрос, сам.задача, решение["экземпляр"], проверенное["команда"], решение["ответ"], решение["основание"])
            требовать(файлы, "Пара существует без квитанции приёма; требуется сверка происхождения")
            план_карточек = вход.подготовить_карточки(сам.корень, карточки, номера, запрос)
            файлы.update(план_карточек)
            with сам.хранилище.изменить() as состояние:
                требовать(событие not in состояние["приёмы"], "Другой процесс уже сохранил намерение; повторите чтение")
                владелец = сам.хранилище.проверить_владельца_под_замком(состояние)
                запись = {"схема": "fum.исполнение-приёма.1", "задача": сам.задача, "корень": str(сам.корень), "ref": владелец["ref"], "база": владелец["HEAD"], "источник": исходная_задача, "экземпляр": решение["экземпляр"], "решение": смысл, "запрос": запрос, "карточки": карточки, "номера": номера, "файлы": файлы, "свидетельства": свидетельства, "реестр": None, "готов": False, "постановка": None, "наблюдение": None}
                проверить_запись(запись)
                состояние["приёмы"][событие] = copy.deepcopy(запись)
        if not запись["готов"]:
            def проверить_исходное(состояние):
                текущая = сам._прочитать(состояние, событие)
                требовать("исправление" not in текущая, "Появилось исправление: повторите исправить-план с тем же JSON")
                требовать(текущая["постановка"] is None and текущая["наблюдение"] is None and событие not in состояние["попытки"], "Исходный приём уже имеет внешний эффект")
                требовать(хранилище.байты(текущая["файлы"]) == хранилище.байты(запись["файлы"]), "Изменился исходный план")
            вход.проверить_решение(сам.корень, источник, исходная_задача, решение)
            вход.проверить_открытый_журнал(сам.корень, запрос)
            сам.хранилище.применить_файлы(событие, "пара и карточки", запись["файлы"], проверить_допуск=проверить_исходное)
            реестр = проверить_планирование(сам.корень)
            сам.хранилище.применить_файлы(событие, "машинный реестр", {ПУТЬ_РЕЕСТРА: реестр}, проверить_допуск=проверить_исходное)
            with сам.хранилище.изменить() as состояние:
                проверить_исходное(состояние)
                текущая = сам._прочитать(состояние, событие)
                сам._сверить_местное(текущая, проверенное)
                текущая["реестр"] = реестр
                текущая["готов"] = True
                запись = copy.deepcopy(текущая)
        else:
            сам._сверить_местное(запись, проверенное)
        return {"событие": событие, "готов": запись["готов"], "номера": copy.deepcopy(запись["номера"]), "свидетельства": copy.deepcopy(запись["свидетельства"])}

    def _сверить_файлы_исправления(сам, запись, *, промежуточные=False):
        for имя, ожидаемое in эффективные_файлы(запись).items():
            путь = вход.обработка.локальный_путь(сам.корень, имя)
            фактическое = вход.обработка.прочитать_файл(путь).decode("utf-8")
            допустимые = (ожидаемое, запись["файлы"][имя]) if промежуточные else (ожидаемое,)
            требовать(фактическое in допустимые, "Файл изменён вне исправляемого плана: " + имя)

    def _допуск_исправления(сам, состояние, исправление, *, промежуточные=False):
        событие = исправление["событие"]
        запись = сам._прочитать(состояние, событие)
        требовать(запись["постановка"] is None and запись["наблюдение"] is None and событие not in состояние["попытки"], "Исправление закрыто после постановки или внешней попытки")
        сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемая_ветка=исправление["ветка"], ожидаемый_коммит=исправление["база"])
        хранилище.гит(сам.корень, "merge-base", "--is-ancestor", запись["база"], исправление["база"])
        требовать(исправление["ожидаемый_план_sha256"] == хранилище.хэш(запись["файлы"]), "Изменён хэш исходного плана")
        if "исправление" in запись:
            требовать(хранилище.байты(запись["исправление"]["намерение"]) == хранилище.байты(исправление), "Разрешён только точный повтор сохранённого исправления")
        else:
            требовать(not запись["готов"] and запись["реестр"] is None, "Готовый приём не исправляется")
        исходный = состояние["этапы"].get(хранилище.ключ_этапа(событие, "пара и карточки"))
        требовать(исходный is not None and исходный["готов"] and исходный["коммит"] is None, "Нет завершённой незакреплённой исходной стадии")
        сам.хранилище._владеть_записью(состояние, исходный)
        требовать(исходный["база"] == запись["база"] and {имя: значение["после"] for имя, значение in исходный["файлы"].items()} == запись["файлы"], "Исходная стадия не соответствует намерению")
        этапы = {"пара и карточки"}
        if "исправление" in запись:
            этапы |= {"исправление карточек " + запись["исправление"]["sha256"], "реестр исправления " + запись["исправление"]["sha256"]}
        требовать(all(этап["этап"] in этапы and этап["коммит"] is None for этап in состояние["этапы"].values() if этап["событие"] == событие), "Есть другая начатая либо закреплённая стадия")
        вход.проверить_открытый_журнал(сам.корень, запись["запрос"])
        сам._сверить_файлы_исправления(запись, промежуточные=промежуточные)
        return запись

    def исправить_план(сам, исправление):
        """Одна явная коррекция после отказа реестра; исходный план неизменяем."""
        проверить_исправление(исправление)
        исправление = copy.deepcopy(исправление)
        событие = исправление["событие"]
        with сам.хранилище.изменить() as состояние:
            запись = сам._допуск_исправления(состояние, исправление, промежуточные=True)
            if "исправление" not in запись:
                кандидат = copy.deepcopy(запись)
                путь_реестра = сам.корень / ПУТЬ_РЕЕСТРА
                хранилище.безопасный_путь(путь_реестра)
                кандидат["схема"] = "fum.исполнение-приёма.2"
                кандидат["исправление"] = {"намерение": исправление, "sha256": хранилище.хэш(исправление), "исходный_отказ": "Ещё не воспроизведён",
                                         "реестр_до": путь_реестра.read_bytes().decode("utf-8") if путь_реестра.exists() else None}
                проверить_запись(кандидат)
                требовать(эффективные_файлы(кандидат) != запись["файлы"], "Исправление не меняет карточки")
                try:
                    проверить_планирование(сам.корень)
                except ValueError as ошибка:
                    кандидат["исправление"]["исходный_отказ"] = str(ошибка)
                else:
                    raise ОшибкаПриёма("Отказ исходного планового реестра не воспроизведён")
                сам._допуск_исправления(состояние, исправление)
                состояние["приёмы"][событие] = кандидат
                запись = кандидат
            elif запись["готов"]:
                сам._сверить_файлы_исправления(запись)
                требовать(вход.обработка.прочитать_файл(сам.корень / ПУТЬ_РЕЕСТРА) == запись["реестр"].encode("utf-8"), "Изменён готовый реестр исправления")
                return {"событие": событие, "исправление_sha256": запись["исправление"]["sha256"], "готов": True, "номера": copy.deepcopy(запись["номера"])}
            запись = copy.deepcopy(запись)
        # Намерение и реально повторно наблюдённый отказ уже долговечны.
        def проверить_карточки(состояние):
            сам._допуск_исправления(состояние, исправление, промежуточные=True)
        def проверить_реестр(состояние):
            сам._допуск_исправления(состояние, исправление)
        квитанция = запись["исправление"]
        файлы = {изменение["путь"]: изменение["содержимое"] for изменение in исправление["файлы"]}
        сам.хранилище.применить_файлы(событие, "исправление карточек " + квитанция["sha256"], файлы,
            ожидаемые_байты={имя: запись["файлы"][имя] for имя in файлы}, ожидаемая_ветка=исправление["ветка"], ожидаемая_база=исправление["база"], проверить_допуск=проверить_карточки)
        реестр = проверить_планирование(сам.корень)
        сам.хранилище.применить_файлы(событие, "реестр исправления " + квитанция["sha256"], {ПУТЬ_РЕЕСТРА: реестр},
            ожидаемые_байты={ПУТЬ_РЕЕСТРА: квитанция["реестр_до"]}, ожидаемая_ветка=исправление["ветка"], ожидаемая_база=исправление["база"], проверить_допуск=проверить_реестр)
        with сам.хранилище.изменить() as состояние:
            текущая = сам._допуск_исправления(состояние, исправление)
            требовать(вход.обработка.прочитать_файл(сам.корень / ПУТЬ_РЕЕСТРА) == реестр.encode("utf-8"), "Изменён сохранённый реестр исправления")
            текущая["реестр"] = реестр
            текущая["готов"] = True
        return {"событие": событие, "исправление_sha256": квитанция["sha256"], "готов": True, "номера": copy.deepcopy(запись["номера"])}

    def закрепить_постановку(сам, событие, коммит, ветка):
        with сам.хранилище.изменить() as состояние:
            запись = сам._прочитать(состояние, событие)
            требовать(запись["готов"], "Местная стадия ещё не готова")
            сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемый_ref=ветка, ожидаемый_коммит=коммит)
            хранилище.гит(сам.корень, "merge-base", "--is-ancestor", запись["база"], коммит)
            if "исправление" in запись:
                хранилище.гит(сам.корень, "merge-base", "--is-ancestor", запись["исправление"]["намерение"]["база"], коммит)
            проверить_инструменты(сам.корень, коммит)
            файлы = {}
            for имя, ожидаемое in {**эффективные_файлы(запись), ПУТЬ_РЕЕСТРА: запись["реестр"]}.items():
                данные = хранилище.гит(сам.корень, "cat-file", "blob", коммит + ":" + имя, сырые=True)
                if имя.startswith("Журнал/"):
                    сверить_журнал_коммита(запись, имя, данные)
                elif имя == ПУТЬ_РЕЕСТРА:
                    требовать(данные == ожидаемое.encode("utf-8"), "Коммит не содержит принятый машинный реестр")
                else:
                    требовать(без_свежести(данные.decode("utf-8")) == без_свежести(ожидаемое), "Коммит изменил принятую карточку либо индекс")
                файлы[имя] = hashlib.sha256(данные).hexdigest()
            постановка = {"коммит": коммит, "ветка": ветка, "файлы": файлы}
            база.проверить_постановку(сам.корень, постановка)
            требовать(запись["постановка"] is None or запись["постановка"] == постановка, "Принятая постановка неизменяема")
            запись["постановка"] = постановка
            return copy.deepcopy(постановка)

    def _аргументы(сам, запись, событие):
        задача = запись["решение"]["задача"]
        требовать(задача is not None, "Смысловое решение не содержит внешнего действия")
        постановка = запись["постановка"]
        поручение = задача["поручение"] + "\n\nИсточник постановки: " + запись["запрос"] + "; точный коммит " + постановка["коммит"] + ".\n"
        поручение += "Приём направления: " + событие + ". Объём: " + запись["решение"]["объём"] + ".\n"
        if задача["режим"] == "создать":
            поручение += ("До первой записи в checkout после чтения маршрута проверь собственные HEAD, полный ref и физический корень. "
                "Если новый worktree находится в detached HEAD на указанном коммите при чистых файлах и индексе, без дополнительного подтверждения создай свободную собственную ветку codex/... от того же полного OID. "
                "Существующие ветки не перемещай. Повторно сверь HEAD, полный ref, физический корень и чистоту файлов и индекса; раннее подтверждение выполняется до содержательной записи, включая создание Журнала. "
                "Вызови сохранённую в этом коммите команду Инструменты/fum-reyestr-planirovaniya/scripts/принять-направление.py с общими --корень-репозитория и --задача, затем подтвердить-начало с --источник собственного первичного JSONL и --коммит "
                + постановка["коммит"] + ". При несовпадении останови запись и сообщи фактические значения. "
                "После раннего подтверждения выполни поручение в своём worktree, проверь результат и сохрани полезный коммит. "
                "Планирование направления само по себе не разрешает предметную реализацию.\n")
            return {"model": "gpt-6-astra", "thinking": "ultra", "title": задача["title"], "prompt": поручение,
                    "target": {"type": "project", "projectId": задача["projectId"], "environment": {"type": "worktree", "startingState": {"type": "branch", "branchName": постановка["ветка"]}}}}
        return {"model": "gpt-6-astra", "thinking": "ultra", "threadId": задача["threadId"], "prompt": поручение}

    def допустить_вызов(сам, источник, исходная_задача, решение):
        событие = событие_источника(исходная_задача, решение["экземпляр"])
        with сам.хранилище.изменить() as состояние:
            запись = сам._прочитать(состояние, событие)
            требовать(хранилище.байты(смысл_решения(решение)) == хранилище.байты(запись["решение"]), "Изменён смысл принятого решения")
            требовать(запись["готов"] and запись["постановка"] is not None, "Нет закреплённого коммита постановки")
            аргументы = сам._аргументы(запись, событие)
        def проверить_допуск(состояние):
            текущая = сам._прочитать(состояние, событие)
            постановка = текущая["постановка"]
            требовать(хранилище.байты(аргументы) == хранилище.байты(сам._аргументы(текущая, событие)), "Изменились аргументы перед сохранением попытки")
            база.проверить_постановку(сам.корень, постановка)
            проверить_инструменты(сам.корень, постановка["коммит"])
            вход.проверить_решение(сам.корень, источник, исходная_задача, решение)
            сам._сверить_карточки(текущая)
            сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемый_ref=постановка["ветка"], ожидаемый_коммит=постановка["коммит"])
        попытка = сам.хранилище.начать_попытку(событие, аргументы, проверить_допуск=проверить_допуск)
        return {**попытка, "событие": событие, "операция": запись["решение"]["задача"]["режим"]}

    def сохранить_ответ(сам, событие, попытка, ответ):
        """Сырой MCP-ответ сохраняется даже без однозначного идентификатора."""
        требовать(type(ответ) is dict, "Нужен полный объект ответа инструмента")
        разобранный = {}
        if ответ.get("isError") is not True:
            варианты = []
            if "threadId" in ответ or "clientThreadId" in ответ:
                варианты.append(ответ)
            if type(ответ.get("structuredContent")) is dict:
                варианты.append(ответ["structuredContent"])
            for часть in ответ.get("content", []) if type(ответ.get("content")) is list else []:
                if type(часть) is dict and часть.get("type") == "text" and type(часть.get("text")) is str:
                    try:
                        значение = хранилище.разобрать(часть["text"].encode("utf-8"))
                        if type(значение) is dict:
                            варианты.append(значение)
                    except ValueError:
                        pass
            извлечённые = [{ключ: значение[ключ] for ключ in ("threadId", "hostId", "clientThreadId") if ключ in значение} for значение in варианты]
            if извлечённые and all(хранилище.байты(значение) == хранилище.байты(извлечённые[0]) for значение in извлечённые):
                разобранный = извлечённые[0]
        with сам.хранилище.изменить() as состояние:
            сам._прочитать(состояние, событие)
        return сам.хранилище.сохранить_ответ(событие, попытка, {**разобранный, "сырой_ответ": ответ})

    def наблюдать(сам, событие, корень_задачи, задача, источник):
        with сам.хранилище.изменить() as состояние:
            запись = сам._прочитать(состояние, событие)
            попытка = состояние["попытки"].get(событие)
            требовать(попытка is not None and запись["постановка"] is not None and запись["решение"]["задача"]["режим"] == "создать", "Нет попытки создания для наблюдения")
            ответ = попытка["ответ"] or {}
            требовать(ответ.get("threadId") in (None, задача), "Наблюдение противоречит прямому ответу runtime")
            граница = база.проверить_нативное_поручение(источник, сам.задача, попытка["аргументы"]["prompt"])
            наблюдение = база.прочитать_подтверждение(Path(корень_задачи), задача, запись["постановка"]["коммит"], источник)
            наблюдение = {**наблюдение, "поручение": граница}
            требовать(запись["наблюдение"] is None or хранилище.байты(запись["наблюдение"]) == хранилище.байты(наблюдение), "Другой результат уже связан с этой попыткой")
            запись["наблюдение"] = наблюдение
            return copy.deepcopy(наблюдение)

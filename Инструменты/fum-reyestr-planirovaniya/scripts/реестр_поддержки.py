def проверить_наблюдение(проверка, корень=None):
    поля = {"дата", "проверил", "вид", "форма", "приём", "допуск", "Россия", "начало", "окончание", "точный_срок", "требования", "ограничения", "неизвестно", "следующий_шаг", "источники", "оформленный_заявитель", "тип_срока"}
    требовать(type(проверка) is dict and set(проверка) == поля, "Неизвестные или неполные поля проверки")
    день = дата(проверка["дата"])
    требовать(текст(проверка["проверил"]) and текст(проверка["следующий_шаг"]) and текст(проверка["точный_срок"]), "Нет автора, срока или следующего шага")
    требовать(проверка["форма"] in ФОРМЫ and проверка["вид"] in ПОЛИТИКА, "Неизвестная форма или вид поддержки")
    требовать(проверка["приём"] in {"открыт", "закрыт", "приостановлен", "неизвестно", "не программа"}, "Неизвестный приём")
    требовать(проверка["оформленный_заявитель"] in {"требуется", "не требуется", "неизвестно"}, "Не определена связь с юридическим профилем")
    требовать(проверка["тип_срока"] in {"интервал", "постоянный", "неизвестно", "не программа"}, "Неизвестный тип срока")
    for ключ in ("допуск", "Россия"):
        требовать(проверка[ключ] in {"да", "нет", "неизвестно"}, "Неизвестный допуск")
    for ключ in ("требования", "ограничения", "неизвестно"):
        требовать(список_текста(проверка[ключ]), "Нужен явный список требований, ограничений и неизвестного")
    начало = дата(проверка["начало"]) if проверка["начало"] is not None else None
    окончание = дата(проверка["окончание"]) if проверка["окончание"] is not None else None
    требовать(проверка["тип_срока"] != "интервал" or окончание is not None, "Для интервала нужна проверенная дата окончания; начало может быть неизвестно")
    требовать(not начало or not окончание or начало <= окончание, "Перевёрнутый срок")
    требовать(type(проверка["источники"]) is list and проверка["источники"], "Нет источников проверки")
    адреса = set()
    for источник in проверка["источники"]:
        требовать(type(источник) is dict and set(источник) == {"URL", "дата_чтения", "вид", "дата_документа", "свидетельство", "официальность", "снимок"}, "Неполный источник")
        требовать(источник["официальность"] in {"подтверждена", "неизвестно"}, "Не определена официальность")
        адрес = urlsplit(источник["URL"])
        требовать(адрес.scheme == "https" and адрес.hostname and not адрес.username and not адрес.password and источник["URL"] not in адреса, "Неофициальный формат или дубль URL")
        адреса.add(источник["URL"])
        требовать(источник["вид"] in {"прямое чтение", "поисковый индекс", "недоступно", "переданное исследование"}, "Неизвестное происхождение чтения")
        требовать(текст(источник["свидетельство"]), "Нет свидетельства источника")
        if источник["дата_чтения"] is not None:
            требовать(дата(источник["дата_чтения"]) <= день, "Чтение из будущего")
        требовать(источник["вид"] != "прямое чтение" or источник["дата_чтения"] is not None, "Не датировано прямое чтение")
        if источник["дата_документа"] is not None:
            требовать(дата(источник["дата_документа"]) <= день, "Документ из будущего")
        if источник["снимок"] is not None:
            снимок = источник["снимок"]
            требовать(type(снимок) is dict and set(снимок) == {"путь", "sha256"}, "Неверный снимок")
            требовать(re.fullmatch(r"[0-9a-f]{64}", снимок["sha256"]), "Неверный хэш снимка")
            if корень is not None:
                путь = normalized_project_relative_path(снимок["путь"], корень, must_exist=True)
                требовать(hashlib.sha256((Path(корень) / путь).read_bytes()).hexdigest() == снимок["sha256"], "Подменён снимок источника")


def оценить(проверка, на_дату, политика=None):
    проверить_наблюдение(проверка)
    сегодня = дата(на_дату)
    политика = политика or ПОЛИТИКА
    прямые = [дата(источник["дата_чтения"]) for источник in проверка["источники"] if источник["вид"] == "прямое чтение"]
    # Самая ранняя опора ограничивает свежесть всего набора условий.
    возраст = (сегодня - min(прямые)).days if прямые else None
    устарело = возраст is None or возраст >= политика[проверка["вид"]]
    непроверено = any(источник["вид"] != "прямое чтение" or источник["официальность"] != "подтверждена" for источник in проверка["источники"])
    истекло = проверка["окончание"] is not None and сегодня > дата(проверка["окончание"])
    последний_день = проверка["окончание"] == на_дату
    будущее = проверка["начало"] is not None and сегодня < дата(проверка["начало"])
    исход, причина = "требует уточнения", "Открытый приём или условия не подтверждены"
    if истекло or проверка["приём"] in {"закрыт", "приостановлен"} or проверка["допуск"] == "нет" or проверка["Россия"] == "нет":
        исход, причина = "недоступный", "Истёк срок" if истекло else "Установлено препятствие входа"
    elif устарело or непроверено or последний_день or будущее or дата(проверка["дата"]) > сегодня:
        причина = "Нужно новое прямое чтение всех условий" if устарело or непроверено else "Нужна проверка точного момента срока" if последний_день else "Приём или наблюдение в будущем"
    elif проверка["приём"] == "неизвестно":
        pass
    elif проверка["вид"] == "программа" and проверка["тип_срока"] not in {"интервал", "постоянный"}:
        причина = "Не установлен срок действия программы"
    elif проверка["оформленный_заявитель"] != "не требуется":
        исход, причина = "условный", "Юридическая форма и регистрация FUM не подтверждены"
    elif проверка["допуск"] == "неизвестно" or проверка["Россия"] == "неизвестно" or проверка["неизвестно"]:
        исход, причина = "условный", "Остаются неизвестные условия или допуск заявителя"
    elif проверка["приём"] == "открыт" or (проверка["приём"] == "не программа" and проверка["вид"] == "подготовка сотрудничества"):
        исход, причина = "подходит для следующего шага", "Подтверждён только указанный следующий шаг"
    доступна = исход == ИСХОДЫ[0] and проверка["вид"] == "программа" and проверка["приём"] == "открыт"
    return {**deepcopy(проверка), "исход": исход, "причина": причина, "доступная_программа": доступна,
        "устарело": устарело, "истёк_срок": истекло, "возраст_опоры_дней": возраст}


def собрать(данные, исходник, на_дату, корень=None):
    дата(на_дату)
    требовать(set(данные) == {"схема", "исходный_sha256", "профиль_FUM", "политика_устаревания_дней", "организации"} and данные["схема"] == "fum.вход-реестра-поддержки.1", "Неизвестная схема входа")
    требовать(данные["исходный_sha256"] == хэш(исходник), "Изменено исходное исследование")
    политика = данные["политика_устаревания_дней"]
    требовать(set(политика) == set(ПОЛИТИКА) and all(type(дней) is int and 1 <= дней <= 365 for дней in политика.values()), "Неверное правило устаревания")
    требовать(данные["профиль_FUM"] == импортировать(исходник)["профиль_FUM"], "Подтверждение нового юридического статуса требует явной миграции профиля")
    происхождение = источниковый_набор(исходник)
    записи = данные["организации"]
    требовать(type(записи) is list and len(записи) == len(происхождение), "Нарушено полное покрытие исходных кандидатов")
    требовать({запись["ид"] for запись in записи} == set(происхождение), "Дубли или подмена идентичности")
    результат = []
    for запись in записи:
        требовать(set(запись) == {"ид", "категории", "польза_FUM", "польза_организации", "варианты"}, "Неизвестная карточка")
        требовать(список_текста(запись["категории"], True) and set(запись["категории"]) <= КАТЕГОРИИ, "Нет категорий")
        требовать(текст(запись["польза_FUM"]) and текст(запись["польза_организации"]), "Не задана взаимная польза")
        требовать(type(запись["варианты"]) is list and запись["варианты"], "Нет исхода рассмотрения организации")
        варианты = []
        имена = set()
        for вариант in запись["варианты"]:
            требовать(set(вариант) == {"ид", "название", "проверки"} and текст(вариант["название"]) and re.fullmatch(r"[а-яё0-9]+(?:-[а-яё0-9]+)*", вариант["ид"]), "Неверный вариант")
            требовать(вариант["ид"] not in имена, "Дубль варианта")
            имена.add(вариант["ид"])
            требовать(type(вариант["проверки"]) is list and вариант["проверки"], "Нет истории проверки")
            предыдущая = None
            for проверка in вариант["проверки"]:
                проверить_наблюдение(проверка, корень)
                требовать(предыдущая is None or дата(проверка["дата"]) >= предыдущая, "Неупорядоченная дата наблюдения")
                предыдущая = дата(проверка["дата"])
            применимые = [проверка for проверка in вариант["проверки"] if проверка["дата"] <= на_дату]
            if применимые:
                оценка = оценить(применимые[-1], на_дату, политика)
            else:
                оценка = {"исход": "требует уточнения", "причина": "На указанную дату ещё нет наблюдения", "доступная_программа": False}
            варианты.append({"ид": вариант["ид"], "название": вариант["название"], **оценка})
        общий = min((вариант["исход"] for вариант in варианты), key=ИСХОДЫ.index)
        результат.append({"ид": запись["ид"], "название": происхождение[запись["ид"]]["исходная_запись"]["название"],
            "происхождение": происхождение[запись["ид"]], "категории": запись["категории"],
            "польза_FUM": запись["польза_FUM"], "польза_организации": запись["польза_организации"], "исход": общий, "варианты": варианты})
    return {"схема": "fum.реестр-поддержки.1", "на_дату": на_дату, "вход_sha256": хэш(данные), "исходный_sha256": хэш(исходник),
        "профиль_FUM": данные["профиль_FUM"], "политика_устаревания_дней": политика, "организации": результат}


def добавить_проверку(данные, исходник, организация, вариант, проверка, ожидаемый_хэш):
    требовать(хэш(данные) == ожидаемый_хэш, "Вход сдвинулся: перечитайте текущие данные")
    собрать(данные, исходник, проверка["дата"])
    новое = deepcopy(данные)
    кандидаты = [часть for часть in новое["организации"] if часть["ид"] == организация]
    требовать(len(кандидаты) == 1, "Неизвестная организация")
    варианты = [часть for часть in кандидаты[0]["варианты"] if часть["ид"] == вариант]
    требовать(len(варианты) == 1, "Неизвестный вариант")
    if проверка == варианты[0]["проверки"][-1]:
        return новое
    варианты[0]["проверки"].append(deepcopy(проверка))
    собрать(новое, исходник, проверка["дата"])
    return новое


def экранировать(значение):
    return str(значение).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("|", "&#124;").replace("[", "&#91;").replace("]", "&#93;")


def таблица(строки):
    ширины = [max(len(строка[номер]) for строка in строки) for номер in range(len(строки[0]))]
    итог = []
    for номер, строка in enumerate(строки):
        итог.append("| " + " | ".join(часть.ljust(ширина) for часть, ширина in zip(строка, ширины)) + " |")
        if номер == 0:
            итог.append("| " + " | ".join("-" * ширина for ширина in ширины) + " |")
    return "\n".join(итог)



def требовать(условие, сообщение):
    if not условие:
        raise ValueError(сообщение)


def текст(значение):
    return type(значение) is str and bool(значение.strip()) and not any(unicodedata.category(буква) == "Cc" for буква in значение)


def список_текста(значение, непустой=False):
    return type(значение) is list and (not непустой or bool(значение)) and all(текст(часть) for часть in значение)


def байты(данные):
    return (json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()


def хэш(данные):
    return hashlib.sha256(байты(данные)).hexdigest()


def разобрать(содержимое):
    def пары(элементы):
        результат = {}
        for ключ, значение in элементы:
            требовать(ключ not in результат, "Повтор ключа JSON")
            результат[ключ] = значение
        return результат
    return json.loads(содержимое, object_pairs_hook=пары)


def дата(значение):
    требовать(type(значение) is str and re.fullmatch(r"\d{4}-\d{2}-\d{2}", значение), "Нужна дата YYYY-MM-DD")
    return date.fromisoformat(значение)


def источниковый_набор(исходник):
    результат = {}
    имена = set()
    for номер, конверт in enumerate(исходник["исследования"]):
        исследование = конверт["исследование"]
        автор = исследование["исследователь"]
        день = исследование.get("дата_исследования", исследование.get("дата_проверки"))
        требовать(текст(автор), "Не задан автор исходного исследования")
        дата(день)
        for позиция, запись in enumerate(исследование["организации"]):
            имя = запись["название"]
            требовать(текст(имя) and имя.casefold() not in имена, "Дубль исходной организации")
            имена.add(имя.casefold())
            ид = "FUM-ORG-" + hashlib.sha256((конверт["исходное_имя"] + "\n" + имя).encode()).hexdigest()[:12]
            требовать(ид not in результат, "Коллизия ID")
            результат[ид] = {"исследование": номер, "позиция": позиция, "исследователь": автор,
                "дата_исследования": день, "исходное_имя": конверт["исходное_имя"],
                "заявленный_sha256_передачи": конверт["sha256_исходной_передачи"], "исходная_запись": deepcopy(запись)}
    требовать(bool(результат), "Пустой исходный набор")
    return результат



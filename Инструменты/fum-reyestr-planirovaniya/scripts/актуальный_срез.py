СТОЛБЦЫ = ['Направление и цель', 'Подтверждённый приоритет', 'Последняя подтверждённая граница',
           'Исполнитель', 'Следующий шаг и зависимость']
ВИДЫ = {'карточка', 'таблица', 'цель', 'акт', 'свидетельство', 'основание'}

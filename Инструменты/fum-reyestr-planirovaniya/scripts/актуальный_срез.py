def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def поля(значение, обязательные, необязательные=()):
    требовать(type(значение) is dict and обязательные <= set(значение)
        and set(значение) <= обязательные | set(необязательные), 'неверный состав полей')


def разобрать_json(данные):
    def пары(элементы):
        результат = {}
        for имя, значение in элементы:
            требовать(имя not in результат, 'повтор JSON-поля')
            результат[имя] = значение
        return результат
    return json.loads(данные.decode('utf-8'), object_pairs_hook=пары,
        parse_constant=lambda значение: требовать(False, 'нечисловая JSON-константа'))


def сериализовать(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False) + '\n').encode('utf-8')


def момент(значение):
    требовать(type(значение) is str and re.fullmatch(
        r'\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d{1,6})?(?:Z|[+-]\d\d:\d\d)', значение),
        'момент требует ISO 8601 с явной зоной')
    return datetime.datetime.fromisoformat(значение.replace('Z', '+00:00')).astimezone(datetime.timezone.utc)


def путь(значение):
    требовать(type(значение) is str and значение and '\\' not in значение
        and not any(ord(буква) < 32 for буква in значение), 'неверный канонический путь')
    части = значение.split('/')
    требовать(all(часть and часть not in ('.', '..') and not часть.startswith('.') for часть in части)
        and not PurePosixPath(значение).is_absolute(), 'неверный канонический путь')
    return значение


def нормализовать_ссылку(цель, источник):
    if цель.startswith('<') and цель.endswith('>'):
        цель = цель[1:-1]
    if re.match(r'^[a-z][a-z0-9+.-]*:', цель) or цель.startswith('#'):
        return цель
    имя, разделитель, фрагмент = цель.partition('#')
    требовать(имя and not имя.startswith('/') and '\\' not in имя, 'ссылка выходит за каноническую область')
    нормальное = posixpath.normpath(posixpath.join(posixpath.dirname(источник), имя))
    путь(нормальное)
    return нормальное + (разделитель + фрагмент if разделитель else '')


def проверить_выбор(выбор):
    поля(выбор, {'схема', 'предел_возраста_секунд', 'источники'})
    требовать(выбор['схема'] == 'fum.выбор-актуального-среза.1', 'неверная схема выбора')
    требовать(type(выбор['предел_возраста_секунд']) is int and выбор['предел_возраста_секунд'] >= 0,
        'нужен явный неотрицательный предел возраста')
    источники = выбор['источники']
    требовать(type(источники) is list and 0 < len(источники) <= 64, 'нужен конечный состав до 64 источников')
    имена = set()
    for источник in источники:
        поля(источник, {'вид', 'путь', 'наблюдение'}, {'шаг', 'зависимости'})
        требовать(источник['вид'] in ВИДЫ, 'неизвестный вид источника')
        имя = путь(источник['путь'])
        требовать(имя not in имена, 'повтор источника')
        имена.add(имя)
        if источник['наблюдение'] is not None:
            момент(источник['наблюдение'])
        if 'шаг' in источник:
            требовать(источник['вид'] == 'акт' and type(источник['шаг']) is str
                and парсер.STEP_CARD_ID_RE.fullmatch(источник['шаг']), 'неверная привязка ACT к шагу')
        if 'зависимости' in источник:
            требовать(источник['вид'] == 'карточка' and type(источник['зависимости']) is list,
                'зависимости карточки задаются явным списком')
            требовать(len(источник['зависимости']) == len(set(источник['зависимости'])), 'повтор зависимости')
            for зависимость in источник['зависимости']:
                путь(зависимость)


def свежесть(наблюдение, оценка, предел):
    возраст = None if наблюдение is None else (оценка - момент(наблюдение)).total_seconds()
    состояние = ('неизвестно' if возраст is None else 'из будущего' if возраст < 0
                 else 'устарело' if возраст > предел else 'свежее')
    return {'момент_наблюдения': наблюдение, 'возраст_секунд': возраст,
            'предел_секунд': предел, 'состояние': состояние}


def строка(номер, цель, источник, оценка, предел):
    return {'идентификатор': номер, 'цель': цель, 'происхождение': {'путь': источник['путь']},
            'приоритет': {'значение': None, 'основание': None, 'актуален': False},
            'исполнитель': None, 'следующий_шаг': {'текст': None, 'цели': [], 'шаги': []},
            'зависимости': [], 'жизненный_статус_карточки': None,
            'наблюдения': [], 'последние_наблюдения': [], 'подтверждение_состояния': None,
            'свежесть': свежесть(источник['наблюдение'], оценка, предел),
            'неизвестность': []}


def идентификатор_шага(цель):
    совпадение = re.search(r'(?<![A-Z0-9])FUM-STEP-\d{4}(?!\d)', цель)
    return None if совпадение is None else совпадение.group()


def разобрать_источник(источник, байты, оценка, предел):
    имя = источник['путь']
    нормализатор = lambda цель: нормализовать_ссылку(цель, имя)
    вид = источник['вид']
    if вид == 'карточка':
        требовать(PurePosixPath(имя).parent.as_posix() == 'Планирование/карточки-шагов', 'карточка вне канонического каталога')
        карточка = парсер.разобрать_карточку_шага(байты, Path(имя), нормализовать_цель=нормализатор)
        запись = строка(карточка['id'], карточка['task'], источник, оценка, предел)
        запись['жизненный_статус_карточки'] = карточка['status']
        запись['следующий_шаг'] = {'текст': карточка['title'], 'цели': [имя], 'шаги': [карточка['id']]}
        запись['зависимости'] = источник.get('зависимости', [])
        запись['наблюдения'].append({'состояние': карточка['status'], 'момент': источник['наблюдение'],
            'основание_проверено': False, 'источник': имя, 'значение': карточка['outcome']})
        return [запись], []
    if вид == 'таблица':
        ячейки = парсер.разобрать_строгую_таблицу(байты, Path(имя), 'Ближайшие согласованные поставки', СТОЛБЦЫ,
            нормализовать_цель=нормализатор, допустить_предтекст=True, допустить_послетекст=True)
        записи = []
        for номер, ряд in enumerate(ячейки, 1):
            запись = строка(имя + '#строка-' + str(номер), ряд[0].text, источник, оценка, предел)
            требовать(ряд[0].text, 'пустая цель таблицы')
            if ряд[1].text.casefold() not in НЕЗАДАННЫЕ:
                запись['приоритет'] = {'значение': ряд[1].text, 'основание': {'путь': имя, 'строка': номер, 'столбец': СТОЛБЦЫ[1]},
                    'актуален': запись['свежесть']['состояние'] == 'свежее'}
            запись['исполнитель'] = ряд[3].text or None
            цели = [ссылка['target'] for ссылка in ряд[4].links]
            запись['следующий_шаг'] = {'текст': ряд[4].text or None, 'цели': цели,
                'шаги': sorted({идентификатор_шага(цель) for цель in цели if идентификатор_шага(цель)})}
            запись['зависимости'] = цели
            запись['наблюдения'].append({'состояние': 'текст планирования', 'момент': источник['наблюдение'],
                'основание_проверено': False, 'источник': имя, 'значение': ряд[2].text})
            записи.append(запись)
        return записи, []
    if вид == 'цель':
        заголовок, _ = парсер.first_level_one_heading(парсер.текст_проверенных_байтов(байты), имя)
        return [строка(имя, заголовок, источник, оценка, предел)], []
    if вид == 'основание':
        парсер.текст_проверенных_байтов(байты)
        return [], []
    запись = разобрать_json(байты)
    if вид == 'акт':
        поля(запись, {'схема', 'координатор', 'исполнитель', 'ветка', 'область', 'постановка', 'хэш_нативного_поручения'})
        требовать(запись['схема'] == 'fum.поручение-дочерней-контрольной-точки.1', 'неподдержанный ACT')
        for имя_поля in ('координатор', 'исполнитель'):
            требовать(type(запись[имя_поля]) is str and str(uuid.UUID(запись[имя_поля])) == запись[имя_поля], 'неверный UUID ACT')
        требовать(запись['координатор'] != запись['исполнитель'], 'UUID ACT совпали')
        требовать(type(запись['ветка']) is str and запись['ветка'].startswith('refs/heads/codex/'), 'неверная ветка ACT')
        требовать(type(запись['область']) is list and запись['область'], 'пустая область ACT')
        for область in запись['область']:
            путь(область[:-1] if область.endswith('/') else область)
        поля(запись['постановка'], {'коммит', 'путь', 'sha256'})
        путь(запись['постановка']['путь'])
        требовать(re.fullmatch('[0-9a-f]{40}|[0-9a-f]{64}', запись['постановка']['коммит'])
            and re.fullmatch('[0-9a-f]{64}', запись['постановка']['sha256'])
            and re.fullmatch('[0-9a-f]{64}', запись['хэш_нативного_поручения']), 'неверные OID/SHA ACT')
        наблюдение = {'состояние': 'назначено', 'момент': источник['наблюдение'], 'основание_проверено': False,
            'источник': имя, 'исполнитель': запись['исполнитель'], 'результат': None, 'шаг': источник.get('шаг'),
            'поручение': запись}
        if 'шаг' in источник:
            return [], [наблюдение]
        ряд = строка(имя, 'Назначение ' + запись['исполнитель'], источник, оценка, предел)
        ряд['исполнитель'] = запись['исполнитель']
        ряд['наблюдения'].append(наблюдение)
        return [ряд], []
    поля(запись, {'схема', 'шаг', 'состояние', 'момент', 'исполнитель', 'результат', 'основание'})
    требовать(запись['схема'] == 'fum.наблюдение-планового-состояния.1'
        and type(запись['шаг']) is str and парсер.STEP_CARD_ID_RE.fullmatch(запись['шаг'])
        and запись['состояние'] in СОСТОЯНИЯ, 'неверное наблюдение')
    момент(запись['момент'])
    if запись['исполнитель'] is not None:
        требовать(type(запись['исполнитель']) is str and запись['исполнитель'].strip(), 'пустой исполнитель')
    if запись['результат'] is not None:
        требовать(type(запись['результат']) is str and re.fullmatch('[0-9a-f]{40}|[0-9a-f]{64}', запись['результат']), 'неверный результат')
    if запись['основание'] is not None:
        поля(запись['основание'], {'путь', 'sha256', 'цитата'})
        путь(запись['основание']['путь'])
        требовать(type(запись['основание']['sha256']) is str and re.fullmatch('[0-9a-f]{64}', запись['основание']['sha256'])
            and type(запись['основание']['цитата']) is str, 'неверное основание')
    return [], [{**запись, 'источник': имя, 'основание_проверено': False}]


def сверить_основание(наблюдение, сырые, срез):
    # Побайтная связь и Git-факты не доказывают полномочие приёмки.
    основание = наблюдение.get('основание')
    if основание is None or основание['путь'] not in сырые:
        return False
    байты = сырые[основание['путь']]
    if hashlib.sha256(байты).hexdigest() != основание['sha256']:
        return False
    состояние, шаг, результат = наблюдение['состояние'], наблюдение['шаг'], наблюдение['результат']
    начало = {'назначено': 'Назначено', 'запущено': 'Запущено', 'результат передан': 'Передано',
              'принято': 'Принято', 'интегрировано': 'Интегрировано', 'снято': 'Снято'}[состояние]
    точная = начало + ' ' + шаг + ('.' if состояние == 'снято' else ': ' + str(результат) + '.')
    if основание['цитата'] != точная or точная not in парсер.текст_проверенных_байтов(байты).splitlines():
        return False
    if состояние == 'снято':
        return результат is None
    if результат is None:
        return False
    try:
        метаданные = срез.метаданные(результат)
        return состояние != 'интегрировано' or (len(метаданные['родители']) == 2 and срез.включает(результат))
    except (ОшибкаОбзора, ValueError):
        return False


def собрать_срез(срез, выбор, момент_оценки, предел, *, профиль=None):
    начало = time.perf_counter_ns()
    вызовы, байты_до = срез.число_вызовов, срез.сумма_байтов
    проверить_выбор(выбор)
    оценка = момент(момент_оценки)
    требовать(type(предел) is int and 100 <= предел <= 2 * 1024 * 1024, 'предел выдачи от 100 до 2097152 байтов')
    возраст = выбор['предел_возраста_секунд']
    чтение = time.perf_counter_ns()
    try:
        метаданные = срез.метаданные()
        источники, сырые = [], {}
        for источник in выбор['источники']:
            имя = источник['путь']
            записи = срез.записи(имя)
            требовать(len(записи) == 1 and записи[0][0] == имя and записи[0][1] in ('100644', '100755')
                and записи[0][2] == 'blob', 'источник не является каноническим обычным файлом: ' + имя)
            объект = (записи[0][3], срез.объект('blob', записи[0][3]))
            сырые[имя] = объект[1]
            происхождение = {'путь': имя, 'вид': источник['вид'], 'режим': записи[0][1], 'объект': объект[0],
                'sha256': hashlib.sha256(объект[1]).hexdigest(), 'байты': len(объект[1])}
            if имя.endswith('.md'):
                происхождение['содержимое_sha256'] = hashlib.sha256(парсер.strip_recency(
                    парсер.текст_проверенных_байтов(объект[1])).encode('utf-8')).hexdigest()
            источники.append(происхождение)
        конец_чтения = time.perf_counter_ns()
        строки, наблюдения = [], []
        for источник in выбор['источники']:
            ряды, события = разобрать_источник(источник, сырые[источник['путь']], оценка, возраст)
            строки.extend(ряды)
            наблюдения.extend(события)
        требовать(len({ряд['идентификатор'] for ряд in строки}) == len(строки), 'повтор идентичности строки')
        по_номеру = {ряд['идентификатор']: ряд for ряд in строки}
        непокрытые = []
        for наблюдение in наблюдения:
            if наблюдение['шаг'] not in по_номеру:
                непокрытые.append({'шаг': наблюдение['шаг'], 'источник': наблюдение['источник']})
                continue
            наблюдение['основание_сверено'] = сверить_основание(наблюдение, сырые, срез)
            ряд = по_номеру[наблюдение['шаг']]
            ряд['наблюдения'].append(наблюдение)
        невошедшие = set()
        неизвестность = []
        for ряд in строки:
            зависимости = []
            for цель in dict.fromkeys(ряд['зависимости']):
                имя = цель.partition('#')[0]
                номер = идентификатор_шага(имя)
                выбран = имя in сырые
                if not выбран and not re.match(r'^[a-z][a-z0-9+.-]*:', цель) and not цель.startswith('#'):
                    невошедшие.add(имя)
                зависимости.append({'путь': цель, 'шаг': номер, 'выбрана': выбран,
                    'жизненный_статус': по_номеру.get(номер, {}).get('жизненный_статус_карточки')})
            ряд['зависимости'] = зависимости
            датированные = [событие for событие in ряд['наблюдения'] if событие.get('момент') is not None]
            if датированные:
                последний_момент = max(момент(событие['момент']) for событие in датированные)
                ряд['последние_наблюдения'] = sorted(
                    [событие for событие in датированные if момент(событие['момент']) == последний_момент],
                    key=lambda событие: сериализовать(событие))
            события_состояния = [событие for событие in датированные if событие['состояние'] in СОСТОЯНИЯ]
            if события_состояния:
                ряд['неизвестность'].append('полномочие приёмки не подтверждено')
                поздние_состояния = [событие for событие in ряд['последние_наблюдения']
                                    if событие['состояние'] in СОСТОЯНИЯ]
                if len({событие['состояние'] for событие in поздние_состояния}) > 1:
                    ряд['неизвестность'].append('противоречащие наблюдения состояния')
                исполнители = {событие.get('исполнитель') for событие in поздние_состояния
                              if событие.get('исполнитель') is not None}
                if len(исполнители) > 1:
                    ряд['неизвестность'].append('противоречащие наблюдения исполнителя')
            for поле, неизвестно in (('приоритет', ряд['приоритет']['значение'] is None),
                    ('исполнитель', ряд['исполнитель'] is None), ('свежесть', ряд['свежесть']['состояние'] != 'свежее')):
                if неизвестно:
                    ряд['неизвестность'].append(поле)
            подтверждение = ряд['подтверждение_состояния']
            состояние = None if подтверждение is None else подтверждение['состояние']
            if состояние not in ('принято', 'интегрировано'):
                ряд['неизвестность'].append('приёмка')
            if состояние != 'интегрировано':
                ряд['неизвестность'].append('интеграция')
            if any(not зависимость['выбрана'] for зависимость in зависимости):
                ряд['неизвестность'].append('зависимости вне состава')
            неизвестность.append({'идентификатор': ряд['идентификатор'], 'поля': ряд['неизвестность'][:],
                'последние_наблюдения': [{ключ: событие[ключ] for ключ in ('состояние', 'момент', 'источник',
                    'исполнитель', 'результат', 'основание_проверено', 'основание_сверено') if ключ in событие}
                    for событие in ряд['последние_наблюдения']]})
        конец_разбора = time.perf_counter_ns()
        результат = {'схема': 'fum.актуальный-срез-планирования.1',
            'снимок': {'коммит': метаданные['коммит'], 'дерево': метаданные['дерево']},
            'момент_оценки': оценка.isoformat(), 'источники': источники, 'строки': строки,
            'полнота': {'область': 'только выбранные источники', 'весь_проект': False,
                'выдача': True, 'всего': len(строки), 'показано': len(строки), 'непоказано': 0,
                'непоказанные_строки': [], 'невошедшие_зависимости': sorted(невошедшие),
                'непокрытые_свидетельства': непокрытые, 'неизвестность': неизвестность,
                'полный_реестр_проверен': False}}
        длина = len(сериализовать(результат))
        if длина > предел:
            # Точная сериализация кандидатов за логарифмическое число проходов.
            # Размер префикса монотонен: строка длиннее заменяющего её идентификатора.
            def выбрать_префикс(число):
                результат['строки'] = строки[:число]
                результат['полнота'].update(выдача=число == len(строки), показано=число,
                    непоказано=len(строки)-число,
                    непоказанные_строки=[ряд['идентификатор'] for ряд in строки[число:]])
                return len(сериализовать(результат))
            требовать(выбрать_префикс(0) <= предел,
                'предел меньше обязательных сведений о происхождении и неполноте')
            низ, верх = 0, len(строки)
            while низ + 1 < верх:
                середина = (низ + верх) // 2
                if выбрать_префикс(середина) <= предел:
                    низ = середина
                else:
                    верх = середина
            длина = выбрать_префикс(низ)
        требовать(длина <= предел, 'предел меньше обязательных сведений о происхождении и неполноте')
        конец = time.perf_counter_ns()
        if профиль is not None:
            профиль.update(чтение_наносекунды=конец_чтения-чтение, разбор_наносекунды=конец_разбора-конец_чтения,
                выдача_наносекунды=конец-конец_разбора, длительность_наносекунды=конец-начало,
                вызовы_гит=срез.число_вызовов-вызовы, прочитано_байтов=срез.сумма_байтов-байты_до,
                объём_результата=длина, токены=None)
        return результат
    except ОшибкаОбзора as ошибка:
        raise ValueError(str(ошибка)) from ошибка

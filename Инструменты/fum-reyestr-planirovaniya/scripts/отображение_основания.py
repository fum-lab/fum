"""Одна адресная поправка производного основания; исходный приём неизменяем."""
import copy
from contextlib import contextmanager
import fcntl
import hashlib
import os
from pathlib import Path
import stat
import tempfile

import исполнитель_приёма as исполнение
import приём_направления as хранение
from приём_направления import требовать

вход = исполнение.вход
обработка = вход.обработка
отчёты = вход.отчёты
ЭТАП = 'поправка отображения основания'


def ша(данные):
    return hashlib.sha256(данные).hexdigest()


def проверить_вход(поправка):
    хранение.поля(поправка, {'схема', 'событие', 'база', 'ветка', 'роль', 'свидетельство',
                         'после_sha256', 'запрос', 'причина', 'исходный_отказ'})
    требовать(поправка['схема'] == 'fum.поправка-отображения-основания.1', 'Неизвестная схема поправки отображения')
    требовать(поправка['роль'] == 'основание', 'Допускается только синтезированное основание')
    требовать(хранение.шестнадцатеричный(поправка['событие']) and хранение.шестнадцатеричный(поправка['база'], 40)
             and хранение.ветка_писателя(поправка['ветка']), 'Неверная идентичность поправки')
    обработка.проверить_свидетельство(поправка['свидетельство'])
    запрос = хранение.путь_результата(поправка['запрос'])
    требовать(len(запрос.parts) == 3 and запрос.parts[0] == 'Журнал' and запрос.name == 'запрос.md', 'Нужен точный запрос нового этапа Журнала')
    требовать(хранение.шестнадцатеричный(поправка['после_sha256']) and вход.содержательный(поправка['причина']), 'Нужны точный результат и причина')
    отказ = поправка['исходный_отказ']
    хранение.поля(отказ, {'путь', 'sha256', 'идентификатор', 'код'})
    хранение.путь_результата(отказ['путь'])
    требовать(хранение.шестнадцатеричный(отказ['sha256']) and хранение.идентификатор_задачи(отказ['идентификатор'])
             and type(отказ['код']) is int and отказ['код'] == 2, 'Нужен сохранённый исходный код 2')
    хранение.байты(поправка)


def прочитать_blob(корень, коммит, имя):
    строки = хранение.гит(корень, 'ls-tree', '-z', коммит, '--', ':(literal)' + имя).split('\0')
    требовать(len(строки) == 2 and строки[-1] == '' and '\t' in строки[0], 'Нет точного исходного blob')
    свойства, путь = строки[0].split('\t', 1)
    части = свойства.split(' ')
    требовать(путь == имя and len(части) == 3 and части[0] in {'100644', '100755'} and части[1] == 'blob', 'Исходный путь не обычный Git-файл')
    return хранение.гит(корень, 'cat-file', 'blob', части[2], сырые=True)


@contextmanager
def замок_отчёта(корень, запрос):
    # Тот же ключ, что у штатной обёртки; безопасное открытие не следует симлинку.
    ключ = отчёты.хэш_содержимого(f'{корень}\0{запрос}'.encode())
    путь = Path(tempfile.gettempdir()).resolve() / f'fum-check-runs-{ключ}.lock'
    хранение.безопасный_путь(путь)
    with os.fdopen(os.open(путь, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600), 'r+b') as поток:
        состояние = os.fstat(поток.fileno())
        требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1 and состояние.st_uid == os.getuid(), 'Необычный замок отчёта')
        fcntl.flock(поток, fcntl.LOCK_EX)
        требовать((путь.stat().st_dev, путь.stat().st_ino) == (состояние.st_dev, состояние.st_ino), 'Замок отчёта подменён')
        yield


def проверить_журналы(корень, задача, запись, поправка):
    прежний = запись['запрос']
    требовать(поправка['свидетельство']['путь'] == Path(прежний).with_name('отчёт.md').as_posix(), 'Поправка вне отчёта исходного приёма')
    for запрос in (прежний, поправка['запрос']):
        _, путь, отчёт, каталог, сессия = отчёты.разрешить_сессию(корень, запрос)
        требовать(сессия == запрос, 'Нужен канонический относительный путь запроса')
        текст = обработка.прочитать_файл(обработка.локальный_путь(корень, запрос)).decode()
        заголовок = вход.заголовок_раздела(текст, 'Идентификатор сеанса Codex')
        конец = вход.конец_раздела(текст, заголовок)
        требовать(текст[заголовок.end():конец].strip() == 'Codex-Thread-ID: ' + задача, 'Чужой Журнал поправки')
        вход.проверить_открытый_журнал(корень, запрос)
        данные = обработка.прочитать_файл(обработка.локальный_путь(корень, отчёт.relative_to(корень).as_posix()))
        требовать('состояние=закрыт'.encode() not in данные, 'Закрытый отчёт не редактируется')
    требовать(прежний != поправка['запрос'], 'Квитанции нужен новый этап Журнала')
    каталог = корень / Path(прежний).parent / 'материалы/запуски-проверок'
    записи = отчёты.прочитать_записи(каталог, прежний, разрешить_раунды=True)
    требовать(all(запись['состояние'] != 'выполняется' for _, запись, _ in записи), 'У отчёта есть активный процесс')
    сохранённые = {}
    for путь, запуск, данные in записи:
        имя = путь.relative_to(корень).as_posix()
        фактическое = обработка.прочитать_файл(обработка.локальный_путь(корень, имя))
        требовать(данные == фактическое == прочитать_blob(корень, поправка['база'], имя), 'Изменено исходное свидетельство проверки')
        сохранённые[имя] = ша(данные)
    отказ = поправка['исходный_отказ']
    найденные = [запуск for путь, запуск, _ in записи if путь.relative_to(корень).as_posix() == отказ['путь']]
    требовать(len(найденные) == 1 and сохранённые[отказ['путь']] == отказ['sha256']
             and найденные[0]['идентификатор'] == отказ['идентификатор']
             and найденные[0]['код_завершения'] == 2, 'Не подтверждён исходный неуспех')
    исходные = хранение.гит(корень, 'ls-tree', '-r', '--name-only', поправка['база'], '--', каталог.relative_to(корень).as_posix()).splitlines()
    требовать(set(исходные) == set(сохранённые), 'Изменён состав исходных проверок')
    return сохранённые


def проверить_истории(корень, база, имя_отчёта):
    область = обработка.локальный_путь(корень, 'Планирование/задачи')
    имена = set()
    if область.exists():
        требовать(область.is_dir(), 'Истории задач не являются каталогом')
        for каталог in область.iterdir():
            обработка.локальный_путь(корень, каталог.relative_to(корень).as_posix())
            if каталог.is_dir():
                путь = каталог / 'обработка-сообщений.jsonl'
                if os.path.lexists(путь):
                    имена.add(путь.relative_to(корень).as_posix())
    исходные = {имя for имя in хранение.гит(корень, 'ls-tree', '-r', '--name-only', база, '--', 'Планирование/задачи').splitlines()
                if имя.endswith('/обработка-сообщений.jsonl')}
    требовать(исходные <= имена, 'Утрачена история 0177 из исходного коммита')
    отпечатки = {}
    for имя in sorted(имена):
        данные = обработка.прочитать_файл(обработка.локальный_путь(корень, имя))
        варианты = [данные]
        if имя in исходные:
            прежде = прочитать_blob(корень, база, имя)
            требовать(данные.startswith(прежде), 'История 0177 переписана или усечена')
            варианты.append(прежде)
        for вариант in варианты:
            требовать(вариант, 'Пустая история не доказывает отсутствие свидетельств')
            шапка = обработка.читатель._разобрать(вариант.splitlines(keepends=True)[0])
            требовать(type(шапка) is dict and шапка.get('задача') == Path(имя).parent.name, 'Неверный владелец истории 0177')
            события = обработка.разобрать_историю(вариант, шапка['задача'], шапка.get('источник'))
            последние = {событие['запись']['экземпляр']: событие['запись'] for событие in события}
            требовать(not any(запись[роль]['путь'] == имя_отчёта for запись in последние.values()
                              for роль in ('команда', 'ответ', 'основание')), 'Отчёт имеет действующее свидетельство 0177')
        отпечатки[имя] = ша(данные)
    return отпечатки


def проверить_потребителей(состояние, запись, событие, имя, ключ):
    корень = запись['корень']
    требовать(событие not in состояние['попытки'] and запись['наблюдение'] is None, 'Исходный приём уже имеет внешнюю попытку')
    for другой, приём in состояние['приёмы'].items():
        if приём.get('корень') == корень and другой != событие:
            требовать(имя not in приём.get('файлы', {}) and not any(свидетельство.get('путь') == имя
                     for свидетельство in приём.get('свидетельства', {}).values()), 'Отчёт используется другим приёмом')
    for другой, этап in состояние['этапы'].items():
        if этап['корень'] != корень or имя not in этап['файлы'] or другой == ключ:
            continue
        требовать(этап['событие'] == событие and этап['этап'] == 'пара и карточки' and этап['готов']
                 and этап['файлы'][имя]['после'] == запись['файлы'][имя], 'Отчёт используется другой стадией')
    for попытка in состояние['попытки'].values():
        if попытка['корень'] == корень:
            требовать(имя not in хранение.байты(попытка['аргументы']).decode(), 'Отчёт используется внешней попыткой')


def поправить(корень, задача, поправка):
    проверить_вход(поправка)
    исполнитель = исполнение.ИсполнительПриёма(корень, задача)
    корень = исполнитель.корень
    событие = поправка['событие']
    ключ = хранение.ключ_этапа(событие, ЭТАП)
    with исполнитель.хранилище.изменить() as состояние:
        запись = copy.deepcopy(исполнитель._прочитать(состояние, событие))
    требовать(запись['готов'] and запись['постановка'] is not None, 'Нужен готовый связанный приём')
    требовать(поправка['база'] == запись['постановка']['коммит'] and поправка['ветка'] == запись['постановка']['ветка'], 'Поправка не соответствует bind')
    требовать(поправка['свидетельство'] == запись['свидетельства']['основание'], 'Нельзя заменить роль или диапазон основания')
    свидетельство = поправка['свидетельство']; имя = свидетельство['путь']
    исходные = прочитать_blob(корень, поправка['база'], имя)
    исполнение.сверить_журнал_коммита(запись, имя, исходные)
    фрагмент = обработка.фрагмент(свидетельство, исходные)
    требовать(фрагмент == запись['решение']['основание'].encode(), 'Основание не совпадает с синтезированным решением')
    требовать(len(фрагмент) > 1 and фрагмент.endswith(b' ') and фрагмент[-2:] != b'  '
             and фрагмент[-2] not in b'\t\r\n', 'Допускается только единственный конечный ASCII-пробел')
    требовать(ша(фрагмент[:-1]) == поправка['после_sha256'], 'Неверный хэш результата диапазона')
    конец = свидетельство['конец']; исправленные = исходные[:конец - 1] + исходные[конец:]
    путь_квитанции = (Path(поправка['запрос']).parent / 'материалы' / ('поправка-основания-' + событие + '.json')).as_posix()
    хранение.путь_результата(путь_квитанции)
    путь_отчёта = обработка.локальный_путь(корень, имя)
    путь_квитанции_на_диске = обработка.локальный_путь(корень, путь_квитанции)
    with замок_отчёта(корень, запись['запрос']):
        проверки = проверить_журналы(корень, задача, запись, поправка)
        истории = проверить_истории(корень, поправка['база'], имя)
        квитанция = {'схема': 'fum.квитанция-поправки-отображения-основания.1', 'задача': задача,
                    'намерение': copy.deepcopy(поправка), 'исходный_приём_sha256': хранение.хэш(запись),
                    'постановка': запись['постановка'], 'отчёт_до_sha256': ша(исходные),
                    'отчёт_после_sha256': ша(исправленные), 'исходные_проверки': проверки, 'истории_0177': истории,
                    'граница': 'Удалён один конечный ASCII-пробел синтезированного основания; исходные свидетельства относятся к прежнему коммиту. Новая запись не является обработкой 0177.'}
        файлы = {путь_квитанции: хранение.байты(квитанция).decode(), имя: исправленные.decode()}
        def проверить_допуск(состояние):
            текущая = исполнитель._прочитать(состояние, событие)
            требовать(текущая == запись, 'Исходный приём изменился после чтения')
            исполнитель.хранилище.проверить_владельца_под_замком(состояние, ожидаемая_ветка=поправка['ветка'], ожидаемый_коммит=поправка['база'])
            исполнение.база.проверить_постановку(корень, запись['постановка'])
            проверить_потребителей(состояние, запись, событие, имя, ключ)
            стадия = состояние['этапы'].get(ключ)
            текущие = обработка.прочитать_файл(путь_отчёта)
            if стадия is None:
                требовать(текущие == исходные, 'До собственной стадии нужны точные исходные байты')
                требовать(not os.path.lexists(путь_квитанции_на_диске), 'Коллизия квитанции поправки')
            else:
                требовать(стадия['файлы'] == {путь_квитанции: {'до': None, 'после': файлы[путь_квитанции]},
                                              имя: {'до': исходные.decode(), 'после': исправленные.decode()}}, 'Допускается только собственный точный повтор')
                требовать(текущие in ((исправленные,) if стадия['готов'] else (исходные, исправленные)), 'Изменённое отображение не восстанавливается')
                if os.path.lexists(путь_квитанции_на_диске):
                    требовать(обработка.прочитать_файл(путь_квитанции_на_диске) == файлы[путь_квитанции].encode(), 'Квитанция изменена')
            требовать(проверить_журналы(корень, задача, запись, поправка) == проверки, 'Состав проверок изменился перед записью')
            требовать(проверить_истории(корень, поправка['база'], имя) == истории, 'Истории 0177 изменились перед записью')
        with исполнитель.хранилище.изменить() as состояние:
            проверить_допуск(состояние)
        исполнитель.хранилище.применить_файлы(событие, ЭТАП, файлы,
            ожидаемые_байты={путь_квитанции: None, имя: исходные.decode()},
            ожидаемая_ветка=поправка['ветка'], ожидаемая_база=поправка['база'], проверить_допуск=проверить_допуск)
        return {'квитанция': путь_квитанции, 'sha256': ша(файлы[путь_квитанции].encode()), 'готов': True}

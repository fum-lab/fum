"""Владелец применяет один адресный план; координатор не пишет в его checkout."""
import os
import hashlib
import math
from pathlib import Path
import sys
import time
import uuid

from приём_направления import требовать, безопасный_путь, разобрать, хэш, текст
from доставка_гит import (выполнить, гит, снимок, служебные_состояния, поддержанное_дерево,
                          чисто, защищённые_файлы, исключить_коллизии)
from доставка_план import построить_план, проверить_план, принять_источник, отношение, сверить_реестр
from доставка_состояние import Квитанции
import доставка_отчёта as отчёт_доставки

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "fum-svyaznostj-rabochej-sessii" / "scripts"))
from захват_вывода import захватить_с_хэшем, прочитать_манифест


class Доставка:
    def __init__(сам, план, корень, задача, реестр, каталог):
        сам.план = проверить_план(план)
        сам.корень, сам.задача, сам.реестр = Path(корень), задача, Path(реестр)
        цели = [цель for цель in план["получатели"] if цель["корень"] == str(сам.корень)]
        требовать(len(цели) == 1, "Нет единственного адресного получателя")
        сам.цель = цели[0]
        сам.хранилище = Квитанции(каталог, план["идентификатор"], корень)
        сам.профиль = []

    def _владелец(сам):
        требовать(Path.cwd().resolve() == сам.корень and os.environ.get("CODEX_THREAD_ID") == сам.задача
                  and сам.задача == сам.цель["владелец"], "Операцию выполняет другой владелец или чужой checkout")
        безопасный_путь(сам.реестр)
        реестр = разобрать(сам.реестр.read_bytes())
        назначение = сам.план.get("назначение")
        сверить_реестр(реестр, назначение)
        ожидаемый = {"задача": сам.задача, "ref": сам.цель["ref"]}
        if сам.цель["ref"] == "refs/heads/fuma":
            ожидаемый["корневая_задача"] = назначение["корневая_задача"]
        требовать(хэш(реестр) == сам.план["владельцы_sha256"] and реестр.get(str(сам.корень)) ==
                  ожидаемый, "Сдвинулся реестр владельцев")
        return снимок(сам.корень, сам.задача, сам.цель["ref"], назначение)

    def _новая(сам):
        наблюдение = сам._владелец()
        требовать(all(наблюдение[ключ] == сам.цель[ключ] for ключ in наблюдение), "Сдвинулся снимок получателя")
        описание = {ключ: сам.план["источник"][ключ] for ключ in ("корень", "ref", "коммит", "владелец", "срез", "приёмка")}
        требовать(принять_источник(описание, сам.план.get("назначение")) == сам.план["источник"], "Изменился принятый источник")
        требовать(отношение(сам.корень, описание["срез"], наблюдение["коммит"]) == (сам.цель["отношение"], сам.цель["патчи"]), "План подменяет отношение истории")
        требовать(not служебные_состояния(сам.корень), "Есть незавершённая Git-операция")
        поддержанное_дерево(сам.корень, сам.план["источник"]["срез"])
        чисто(сам.корень)
        return {"схема": "fum.квитанция-обратной-доставки.2", "план": сам.план["идентификатор"],
                "корень": str(сам.корень), "ref": сам.цель["ref"], "владелец": сам.задача,
                "источник": сам.план["источник"]["срез"], "до": сам.цель["коммит"],
                "стадия": "подготовлено", "дерево": None, "защищённые": защищённые_файлы(сам.корень),
                "проверка": None, "коммит": None, "публикация": None, "получатель": "unknown", "основание": None,
                "отчёт": None}

    def _после_слияния(сам):
        """Граница наблюдения реального эффекта; используется аварийной фикстурой."""

    def _сверить_защиту(сам, данные):
        требовать(защищённые_файлы(сам.корень) == данные["защищённые"], "Изменились untracked/ignored; нужна сверка владельца")

    def _восстановить(сам, данные):
        наблюдение = сам._владелец()
        if данные.get("отчёт") is not None:
            return сам._восстановить_отчёт(данные, наблюдение)
        сам._сверить_защиту(данные)
        состояния = служебные_состояния(сам.корень)
        требовать(set(состояния) <= {"MERGE_HEAD"}, "Неподдержанная Git-операция при восстановлении")
        поддержанное_дерево(сам.корень, данные["источник"], конфликт=данные["стадия"] in ("применяется", "конфликт"))
        if "MERGE_HEAD" in состояния:
            требовать(данные["стадия"] != "подготовлено", "Слияние возникло до намерения")
            требовать(наблюдение["коммит"] == данные["до"] and гит(сам.корень, "rev-parse", "MERGE_HEAD") == данные["источник"]
                      and гит(сам.корень, "rev-parse", "ORIG_HEAD") == данные["до"], "Это чужое либо изменившееся слияние")
            if гит(сам.корень, "ls-files", "-u"):
                требовать(данные["стадия"] in ("применяется", "конфликт"), "После проверки возник конфликт")
                данные["стадия"] = "конфликт"
                return данные
            чисто(сам.корень, индекс=False)
            дерево = гит(сам.корень, "write-tree")
            требовать(данные["дерево"] == дерево, "Состав слияния отличается от сохранённого намерения")
            if данные["стадия"] == "применяется":
                данные["стадия"] = "применено"
            требовать(данные["стадия"] in ("применено", "проверяется", "проверено"), "Конфликт требует отдельного решения владельца")
            return данные
        if данные["стадия"] in ("подготовлено", "применяется", "эффект не подтверждён") and наблюдение["коммит"] == данные["до"]:
            чисто(сам.корень)
            if данные["стадия"] == "применяется":
                # Нельзя приписать исчезнувшему эффекту исход или повторить его вслепую.
                данные["стадия"] = "эффект не подтверждён"
            return данные
        if данные["стадия"] == "содержание уже доставлено":
            требовать(наблюдение["коммит"] == данные["до"], "Получатель сдвинулся после сверки содержания")
            чисто(сам.корень)
            return данные
        требовать(данные["стадия"] in ("проверено", "закоммичено"), "Слияние исчезло до подтверждённой проверки")
        чисто(сам.корень)
        требовать(гит(сам.корень, "rev-list", "--parents", "-n", "1", наблюдение["коммит"]).split()[1:] ==
                  [данные["до"], данные["источник"]] and наблюдение["дерево"] == данные["дерево"], "Коммит не соответствует проверенному слиянию")
        требовать(данные["коммит"] in (None, наблюдение["коммит"]), "Сдвинулся принятый коммит")
        данные["коммит"] = наблюдение["коммит"]
        данные["стадия"] = "закоммичено"
        return данные

    def применить(сам):
        начало = time.monotonic_ns()
        сам._владелец()
        with сам.хранилище.замок() as хранилище:
            данные = хранилище.прочитать()
            if данные is not None:
                прежние = хэш(данные)
                данные = сам._восстановить(данные)
                if данные["стадия"] != "подготовлено":
                    if хэш(данные) != прежние:
                        хранилище.сохранить(данные)
                    return данные
            else:
                требовать(сам.цель["отношение"] == "недоставленные коммиты", "Нужна смысловая сверка переноса; автоматический merge не назначен")
                данные = сам._новая()
                исключить_коллизии(сам.корень, данные["источник"], данные["защищённые"])
                предварительное = выполнить(сам.корень, "merge-tree", "--write-tree", данные["до"], данные["источник"], допустимые=(0, 1))
                данные["дерево"] = предварительное.stdout.decode().splitlines()[0]
                хранилище.сохранить(данные)
            сам._новая()  # Повтор допуска непосредственно перед эффектом.
            данные["стадия"] = "применяется"
            хранилище.сохранить(данные)
            выполнить(сам.корень, "merge", "--no-commit", "--no-ff", "--no-edit", "--no-overwrite-ignore", данные["источник"], допустимые=(0, 1, 128))
            сам._после_слияния()
            данные = сам._восстановить(данные)
            хранилище.сохранить(данные)
        сам.профиль.append({"стадия": "применение", "длительность_наносекунды": time.monotonic_ns() - начало})
        return данные

    def состояние(сам):
        сам._владелец()
        with сам.хранилище.замок() as хранилище:
            данные = хранилище.прочитать()
            требовать(данные is not None, "Нет квитанции")
            прежние = хэш(данные)
            данные = сам._восстановить(данные)
            if прежние != хэш(данные):
                хранилище.сохранить(данные)
            return данные

    def проверить(сам, команда, тайм_аут=60, *, запрос=None, корневая_задача=None):
        требовать(type(команда) is list and команда and all(isinstance(часть, str) and часть and "\0" not in часть for часть in команда), "Нужен точный argv проверки")
        требовать((запрос is None) == (корневая_задача is None), "Запрос и корневая задача задаются вместе")
        if запрос is not None and "назначение" in сам.план:
            требовать(корневая_задача == сам.план["назначение"]["корневая_задача"], "Отчёт относится к другой корневой задаче назначения")
        требовать(type(тайм_аут) in (int, float) and math.isfinite(тайм_аут) and 0 < тайм_аут <= (3590 if запрос is not None else 3600), "Недопустимый тайм-аут")
        сам._владелец()
        with сам.хранилище.замок() as хранилище:
            данные = хранилище.прочитать()
            требовать(данные is not None, "Сначала нужно применение")
            данные = сам._восстановить(данные)
            требовать(данные["стадия"] in ("применено", "проверяется", "проверено"), "Стадия не допускает проверку")
            требовать(данные.get("отчёт") is None, "Назначенная отчётная проверка не повторяется автоматически")
            if запрос is not None:
                данные["отчёт"] = отчёт_доставки.подготовить(сам.корень, запрос, корневая_задача, данные["дерево"], команда, тайм_аут)
                данные["схема"] = "fum.квитанция-обратной-доставки.2"
                команда = данные["отчёт"]["команда"]
            данные["стадия"] = "проверяется"
            каталог_захвата = сам.хранилище.каталог / ("проверка-" + str(uuid.uuid4()))
            данные["проверка"] = {"argv_sha256": хэш(команда), "код": None, "длительность_наносекунды": None,
                                  "каталог": str(каталог_захвата), "манифест_sha256": None, "полнота": False}
            хранилище.сохранить(данные)
            начало = time.monotonic_ns()
            манифест, контрольный_хэш = захватить_с_хэшем(команда, каталог_захвата, сам.корень, сам.задача,
                                                        тайм_аут=тайм_аут + 10 if запрос is not None else тайм_аут)
            данные["проверка"].update(код=манифест["код_процесса"], длительность_наносекунды=time.monotonic_ns() - начало,
                                      манифест_sha256=контрольный_хэш, полнота=манифест["полнота"])
            if запрос is not None:
                хранилище.сохранить(данные)
                сам._после_проверки()
                данные = сам._восстановить(данные)
                хранилище.сохранить(данные)
                return данные
            сам._восстановить(данные)
            данные["стадия"] = "проверено" if манифест["код_процесса"] == 0 and манифест["полнота"] else "применено"
            хранилище.сохранить(данные)
            return данные

    def _после_проверки(сам):
        """Аварийная граница между терминалом проверки и предпросмотром."""

    def _восстановить_отчёт(сам, данные, наблюдение):
        граница = данные["отчёт"]
        состояния = служебные_состояния(сам.корень)
        требовать(set(состояния) <= {"MERGE_HEAD"}, "Посторонняя Git-операция")
        поддержанное_дерево(сам.корень, данные["источник"])
        if "MERGE_HEAD" not in состояния:
            требовать(данные["стадия"] in ("проверено", "закоммичено"), "Слияние исчезло до подтверждения индекса")
            чисто(сам.корень)
            требовать(гит(сам.корень, "rev-list", "--parents", "-n", "1", наблюдение["коммит"]).split()[1:] ==
                      [данные["до"], данные["источник"]] and наблюдение["дерево"] == данные["дерево"], "Коммит отличается от подтверждённого дерева")
            отчёт_доставки.сверить(сам.корень, граница, итоговый=True)
            отчёт_доставки.сверить_дерево(сам.корень, граница, данные["дерево"])
            требовать(данные["коммит"] in (None, наблюдение["коммит"]), "Сдвинулся принятый коммит")
            данные.update(коммит=наблюдение["коммит"], стадия="закоммичено")
            return данные
        требовать(наблюдение["коммит"] == данные["до"] and гит(сам.корень, "rev-parse", "MERGE_HEAD") == данные["источник"]
                  and гит(сам.корень, "rev-parse", "ORIG_HEAD") == данные["до"], "Чужое слияние при отчётной проверке")
        if данные["стадия"] == "проверяется":
            требовать(гит(сам.корень, "write-tree") == граница["дерево_слияния"], "Индекс изменился до завершения проверки")
            каталог = Path(данные["проверка"]["каталог"])
            путь = каталог / "манифест.json"
            безопасный_путь(путь)
            требовать(путь.is_file(), "Ответ проверки отсутствует; повторный запуск запрещён")
            контрольный_хэш = hashlib.sha256(путь.read_bytes()).hexdigest()
            требовать(данные["проверка"]["манифест_sha256"] in (None, контрольный_хэш), "Подменён манифест проверки")
            _, манифест = прочитать_манифест(каталог, контрольный_хэш)
            вызов = разобрать((каталог / "вызов.json").read_bytes())
            требовать(вызов["команда"] == граница["команда"] and вызов["корень"] == str(сам.корень)
                      and вызов["задача"] == сам.задача and манифест["задача"] == сам.задача
                      and манифест["вызов_sha256"] == hashlib.sha256((каталог / "вызов.json").read_bytes()).hexdigest(), "Чужой захват проверки")
            for имя, сведения in манифест["каналы"].items():
                файл = каталог / (имя + ".bin")
                безопасный_путь(файл)
                требовать(файл.stat().st_size == сведения["байты"] and hashlib.sha256(файл.read_bytes()).hexdigest() == сведения["sha256"], "Повреждён полный вывод проверки")
            данные["проверка"].update(код=манифест["код_процесса"], манифест_sha256=контрольный_хэш, полнота=манифест["полнота"])
            разница, запись = отчёт_доставки.сверить(сам.корень, граница, предпросмотр=True)
            граница["разница"] = разница
            успешна = манифест["полнота"] and манифест["код_процесса"] == 0 and запись["статус"] == "успешно" and запись["код_завершения"] == 0
            данные["стадия"] = "ожидается индекс" if успешна else "проверка не пройдена"
        else:
            требовать(данные["стадия"] in ("ожидается индекс", "проверка не пройдена", "проверено"), "Неизвестная стадия отчётной проверки")
            отчёт_доставки.сверить(сам.корень, граница)
        if данные["стадия"] == "проверено":
            чисто(сам.корень, индекс=False)
            требовать(гит(сам.корень, "write-tree") == данные["дерево"], "Подтверждённый индекс изменился")
        return данные

    def подтвердить_индекс(сам):
        сам._владелец()
        with сам.хранилище.замок() as хранилище:
            данные = сам._восстановить(хранилище.прочитать())
            требовать(данные["стадия"] in ("ожидается индекс", "проверено") and данные.get("отчёт") is not None, "Нет успешной отчётной проверки")
            чисто(сам.корень, индекс=False)
            итоговое = гит(сам.корень, "write-tree")
            отчёт_доставки.сверить_дерево(сам.корень, данные["отчёт"], итоговое)
            данные.update(дерево=итоговое, стадия="проверено")
            хранилище.сохранить(данные)
            return данные

    def подтвердить_коммит(сам):
        данные = сам.состояние()
        требовать(данные["стадия"] == "закоммичено", "Проверенный коммит ещё не наблюдён")
        return данные

    def подтвердить_получение(сам, основание):
        требовать(текст(основание), "Нужно решение получателя")
        сам._владелец()
        with сам.хранилище.замок() as хранилище:
            данные = хранилище.прочитать()
            if данные is None:
                требовать(сам.цель["отношение"] in ("в предках", "равное дерево", "эквивалентные патчи"), "Частичный перенос требует отдельного решения и нового плана")
                данные = сам._новая()
                данные["стадия"] = "содержание уже доставлено"
                данные["дерево"] = сам.цель["дерево"]
            else:
                данные = сам._восстановить(данные)
                требовать(данные["стадия"] in ("закоммичено", "содержание уже доставлено"), "Приём получателем требует проверенного коммита либо явной сверки эквивалентности")
            данные["получатель"], данные["основание"] = "подтверждено", основание
            хранилище.сохранить(данные)
            return данные

    def проверить_публикацию(сам):
        сам._владелец()
        with сам.хранилище.замок() as хранилище:
            данные = сам._восстановить(хранилище.прочитать())
            требовать(данные["стадия"] == "закоммичено", "Нет проверенного коммита")
            адреса = гит(сам.корень, "remote", "get-url", "--push", "--all", "origin").splitlines()
            требовать(len(адреса) == 1, "Неоднозначный публикационный origin")
            ответ = гит(сам.корень, "ls-remote", "--refs", адреса[0], данные["ref"]).splitlines()
            требовать(ответ == [данные["коммит"] + "\t" + данные["ref"]], "Удалённый OID не подтверждает публикацию")
            данные["публикация"] = {"коммит": данные["коммит"], "ref": данные["ref"], "адрес_sha256": хэш(адреса[0])}
            хранилище.сохранить(данные)
            return данные

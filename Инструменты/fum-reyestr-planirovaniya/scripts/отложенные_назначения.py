def ключ_пакета(пакет):
    return хранение.хэш({"схема": "fum.ключ-пакета-отложенных-назначений.1", "источник": пакет["исходная_задача"], "экземпляр": пакет["решение"]["экземпляр"]})


def смысл(пакет):
    return {ключ: прежний.смысл_решения(значение) if ключ == "решение" else copy.deepcopy(значение)
            for ключ, значение in пакет.items() if ключ != "источник"}


def манифест_коммита(корень, коммит, файлы):
    требовать(хранение.шестнадцатеричный(коммит, 40) and гит(корень, "cat-file", "-t", коммит).strip() == "commit", "Нужен точный исходный коммит")
    требовать(type(файлы) is dict and файлы, "Нужен полный манифест постановки")
    прочитанные = {}
    for имя, отпечаток in файлы.items():
        путь = хранение.путь_результата(имя)
        требовать(хранение.шестнадцатеричный(отпечаток), "Неверный хэш манифеста")
        запись = гит(корень, "ls-tree", "-z", коммит, "--", ":(literal)" + str(путь)).split("\0")
        требовать(len(запись) == 2 and запись[-1] == "" and "\t" in запись[0], "Нет файла манифеста: " + имя)
        свойства, наблюдаемый = запись[0].split("\t", 1)
        части = свойства.split()
        требовать(наблюдаемый == имя and len(части) == 3 and части[0] in {"100644", "100755"} and части[1] == "blob", "Нужен обычный blob постановки")
        данные = гит(корень, "cat-file", "blob", части[2], сырые=True)
        требовать(hashlib.sha256(данные).hexdigest() == отпечаток, "Изменён исходный blob: " + имя)
        прочитанные[имя] = данные
    return прочитанные


def проверить_источники(корень, пакет, состояние):
    for назначение in пакет["назначения"]:
        источник = назначение["исходная_постановка"]
        хранение.поля(источник, {"коммит", "дерево", "событие", "сохранённая_запись_sha256", "файлы"})
        файлы = манифест_коммита(корень, источник["коммит"], источник["файлы"])
        требовать(хранение.шестнадцатеричный(источник["дерево"], 40) and гит(корень, "rev-parse", источник["коммит"] + "^{tree}").strip() == источник["дерево"], "Изменено дерево исторической постановки")
        карточки = [данные.decode("utf-8") for имя, данные in файлы.items() if имя.startswith("Планирование/карточки-шагов/") and назначение["направление"] in хранение.идентичности_карточки(имя, данные.decode("utf-8"))]
        требовать(len(карточки) == 1 and re.search(r'(?m)^status\s*=\s*"active"\s*$', карточки[0]), "Нет единственной активной исходной карточки направления")
        событие = источник["событие"]
        известные = {ключ: запись for ключ, запись in состояние["приёмы"].items()
                     if type(запись) is dict and запись.get("схема") in {"fum.исполнение-приёма.1", "fum.исполнение-приёма.2"}
                     and type(запись.get("постановка")) is dict
                     and запись["постановка"].get("коммит") == источник["коммит"]
                     and any(назначение["направление"] in Path(имя).name for имя in запись["постановка"].get("файлы", {}))}
        требовать(not известные or событие in известные, "Нельзя скрыть известный прежний приём историческим null")
        требовать(not any(ключ in состояние["попытки"] for ключ in известные), "Направление уже имеет внешнюю попытку прежнего приёма")
        обязательные = {имя for имя in источник["файлы"] if not имя.startswith("Журнал/")}
        требовать(обязательные <= set(назначение["файлы_запуска"]), "Новый запуск не содержит полный предметный набор исходной постановки")
        if событие is None:
            требовать(источник["сохранённая_запись_sha256"] is None, "Историческому источнику без события не присваивается квитанция")
        else:
            требовать(хранение.шестнадцатеричный(событие), "Неверное исходное событие")
            запись = состояние["приёмы"].get(событие)
            прежний.проверить_запись(запись)
            требовать(хранение.хэш(запись) == источник["сохранённая_запись_sha256"], "Изменена историческая запись приёма")
            требовать(запись["готов"] and запись["решение"]["задача"] is None and запись["постановка"] is not None, "Нужен готовый прежний приём без задачи")
            требовать(запись["постановка"]["коммит"] == источник["коммит"] and запись["постановка"]["файлы"] == источник["файлы"], "Сокращён либо заменён полный исходный манифест")
            требовать(событие not in состояние["попытки"], "У прежнего приёма уже есть внешняя попытка")


def извлечь_ответ(ответ):
    требовать(type(ответ) is dict, "Нужен полный объект MCP-ответа")
    хранение.проверить_структуру_данных(ответ)
    варианты = []
    if ответ.get("isError") is not True:
        if "threadId" in ответ or "clientThreadId" in ответ:
            варианты.append(ответ)
        if type(ответ.get("structuredContent")) is dict:
            варианты.append(ответ["structuredContent"])
        for часть in ответ.get("content", []) if type(ответ.get("content")) is list else []:
            if type(часть) is dict and часть.get("type") == "text" and type(часть.get("text")) is str:
                try:
                    значение = хранение.разобрать(часть["text"].encode("utf-8"))
                    if type(значение) is dict:
                        варианты.append(значение)
                except ValueError:
                    pass
    найденные = [{ключ: значение[ключ] for ключ in ("threadId", "clientThreadId", "hostId") if ключ in значение} for значение in варианты]
    конфликт = bool(найденные) and (any(значение != найденные[0] for значение in найденные)
        or any(type(значение) is not str or not значение for часть in найденные for значение in часть.values())
        or any("threadId" in часть and not хранение.идентификатор_задачи(часть["threadId"]) for часть in найденные))
    return {**(найденные[0] if найденные and not конфликт else {}), "противоречивые_идентификаторы": конфликт, "сырой_ответ": ответ}


class ИсполнительНазначений:
    def __init__(сам, корень, задача):
        сам.корень = Path(корень).resolve()
        сам.задача = задача
        сам.хранилище = хранение.Хранилище(сам.корень, задача)

    def _прочитать(сам, состояние, ключ):
        запись = состояние["приёмы"].get(ключ)
        хранение.поля(запись, {"схема", "смысл", "план", "задача", "корень", "ref", "база", "готов", "постановка", "наблюдения"})
        требовать(запись["схема"] == СХЕМА_ЗАПИСИ and запись["задача"] == сам.задача and запись["корень"] == str(сам.корень), "Чужой либо неизвестный пакет")
        требовать(ключ_пакета(запись["смысл"]) == ключ and type(запись["готов"]) is bool and type(запись["наблюдения"]) is dict, "Повреждена идентичность пакета")
        план = запись["план"]
        хранение.поля(план, {"пакет", "назначения", "файлы", "входы_запуска", "база", "ref", "смысл_sha256", "sha256"})
        требовать(план["sha256"] == хранение.хэш({имя: значение for имя, значение in план.items() if имя != "sha256"}) and план["пакет"] == ключ and план["смысл_sha256"] == хранение.хэш(запись["смысл"]), "Повреждён сухой план сохранённого пакета")
        требовать((план["база"], план["ref"]) == (запись["база"], запись["ref"]), "Подменена база пакета")
        return запись

    def _план(сам, пакет, состояние):
        хранение.поля(пакет, {"схема", "источник", "исходная_задача", "решение", "разрешения", "запрос", "назначения"})
        требовать(пакет["схема"] == СХЕМА and хранение.идентификатор_задачи(пакет["исходная_задача"]), "Неизвестная схема или источник пакета")
        назначения = пакет["назначения"]
        требовать(type(назначения) is list and 1 <= len(назначения) <= 6, "Разрешён конечный пакет от одного до шести назначений")
        требовать(type(пакет["решение"]) is dict and пакет["решение"].get("задача") is None, "Общее решение не является отдельным внешним вызовом")
        требовать(type(пакет["разрешения"]) is list and пакет["решение"]["экземпляр"] in пакет["разрешения"], "Пакет требует собственного подтверждённого человеческого разрешения")
        направления = set()
        for назначение in назначения:
            хранение.поля(назначение, {"направление", "исходная_постановка", "файлы_запуска", "объём", "актуальность", "поздние", "ограничения", "антидубликат", "задача"})
            номер = назначение["направление"]
            требовать(type(номер) is str and re.fullmatch(r"FUM-STEP-[0-9]{4}", номер) and номер not in направления, "Повторное либо неверное направление")
            направления.add(номер)
            требовать(назначение["объём"] in {"планирование", "реализация", "описание"} and назначение["актуальность"] in {"актуально", "уточнено"}, "Не разрешён предметный объём")
            требовать(type(назначение["поздние"]) is list and set(назначение["поздние"]) <= set(пакет["решение"]["поздние"]), "Не рассмотрено позднее ограничение направления")
            требовать(назначение["актуальность"] != "уточнено" or назначение["поздние"], "Уточнение требует источника")
            требовать(all(вход.содержательный(назначение[ключ]) for ключ in ("ограничения", "антидубликат")), "Нет границ или проверки дубликатов")
            задача = назначение["задача"]
            хранение.поля(задача, {"режим", "projectId", "title", "поручение"})
            требовать(задача["режим"] == "создать" and all(вход.содержательный(задача[ключ]) for ключ in ("projectId", "title", "поручение")), "Нужна полная явная постановка создания")
            требовать(type(назначение["файлы_запуска"]) is dict and назначение["файлы_запуска"], "Нет предметных файлов нового запуска")
        # Один полный разбор первичного источника на границе, а не шесть повторов.
        решение = {**пакет["решение"], "задача": {**назначения[0]["задача"], "разрешение": пакет["разрешения"]}}
        проверенное = вход.проверить_решение(сам.корень, пакет["источник"], пакет["исходная_задача"], решение)
        ключ = ключ_пакета(пакет)
        существующая = состояние["приёмы"].get(ключ)
        if существующая is not None:
            запись = сам._прочитать(состояние, ключ)
            требовать(хранение.байты(запись["смысл"]) == хранение.байты(смысл(пакет)), "Неизменяемый пакет уже принят с другим составом или смыслом")
        for иной_ключ, иная in состояние["приёмы"].items():
            if иной_ключ != ключ and type(иная) is dict and иная.get("схема") == СХЕМА_ЗАПИСИ:
                требовать(not направления.intersection(часть["направление"] for часть in иная["смысл"]["назначения"]), "Направление уже назначено другим пакетом")
        проверить_источники(сам.корень, пакет, состояние)
        запрос = пакет["запрос"]
        требовать(type(запрос) is str and re.fullmatch(r"Журнал/[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}-[0-9]{2}-[0-9]{2}_MSK_[^/]+/запрос\.md", запрос), "Нужен собственный канонический Журнал")
        путь = вход.обработка.локальный_путь(сам.корень, запрос)
        текст = вход.обработка.прочитать_файл(путь).decode("utf-8")
        раздел = вход.заголовок_раздела(текст, "Текст запроса")
        требовать(текст[раздел.end():вход.конец_раздела(текст, раздел)].count(проверенное["команда"]) == 1, "Команда собственного Журнала не подтверждена")
        владелец_журнала = вход.заголовок_раздела(текст, "Идентификатор сеанса Codex")
        требовать(текст[владелец_журнала.end():вход.конец_раздела(текст, владелец_журнала)].strip() == "Codex-Thread-ID: " + сам.задача, "Чужой владелец Журнала")
        if существующая is None or not существующая["готов"]:
            вход.проверить_открытый_журнал(сам.корень, запрос)
            отчёт = вход.обработка.прочитать_файл(путь.with_name("отчёт.md")).decode("utf-8")
            требовать("состояние=закрыт" not in отчёт, "Закрытый отчёт не возобновляется")
        ключи = {часть["направление"]: хранение.хэш({"схема": "fum.ключ-отложенного-назначения.1", "пакет": ключ, "направление": часть["направление"], "исходный_коммит": часть["исходная_постановка"]["коммит"]}) for часть in назначения}
        каталог = Path(запрос).parent / "материалы/назначения"
        файлы = {}
        for часть in назначения:
            данные = {"схема": "fum.постановка-отложенного-назначения.1", "пакет": ключ, "назначение": ключи[часть["направление"]], "исходная_задача": пакет["исходная_задача"], "экземпляр": пакет["решение"]["экземпляр"], "команда": проверенное["команда"], "основание": пакет["решение"]["основание"], "направление": часть}
            файлы[(каталог / (часть["направление"] + ".json")).as_posix()] = хранение.байты(данные).decode("utf-8")
        for имя, содержимое in файлы.items():
            путь_материала = вход.обработка.локальный_путь(сам.корень, имя)
            if путь_материала.exists():
                требовать(существующая is not None and путь_материала.read_bytes() == содержимое.encode("utf-8"), "Файл назначения уже занят другими байтами")
        манифест = {}
        for часть in назначения:
            карточки_запуска = []
            for имя, отпечаток in часть["файлы_запуска"].items():
                требовать(имя not in манифест or манифест[имя] == отпечаток, "Разные версии общего входа запуска")
                файл = вход.обработка.локальный_путь(сам.корень, имя)
                требовать(хранение.шестнадцатеричный(отпечаток) and hashlib.sha256(вход.обработка.прочитать_файл(файл)).hexdigest() == отпечаток, "Изменён предметный вход запуска: " + имя)
                манифест[имя] = отпечаток
                if имя.startswith("Планирование/карточки-шагов/") and часть["направление"] in хранение.идентичности_карточки(имя, вход.обработка.прочитать_файл(файл).decode("utf-8")):
                    карточки_запуска.append(имя)
            требовать(len(карточки_запуска) == 1, "Нет единственной карточки направления в новом запуске")
        владелец = сам.хранилище._наблюдать_владельца()
        план = {"пакет": ключ, "назначения": ключи, "файлы": файлы, "входы_запуска": манифест, "база": существующая["база"] if существующая else владелец["HEAD"], "ref": владелец["ref"], "смысл_sha256": хранение.хэш(смысл(пакет))}
        return {**план, "sha256": хранение.хэш(план)}

    def предпросмотр(сам, пакет):
        return сам._план(пакет, сам.хранилище.прочитать())

    def подготовить(сам, пакет, ожидаемый):
        план = сам.предпросмотр(пакет)
        требовать(план["sha256"] == ожидаемый, "Изменён проверенный сухой план")
        сам.хранилище.занять()
        ключ = план["пакет"]
        with сам.хранилище.изменить() as состояние:
            проверенный = сам._план(пакет, состояние)
            требовать(проверенный == план, "Изменён план под замком")
            сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемая_ветка=план["ref"])
            if ключ not in состояние["приёмы"]:
                состояние["приёмы"][ключ] = {"схема": СХЕМА_ЗАПИСИ, "смысл": смысл(пакет), "план": план, "задача": сам.задача, "корень": str(сам.корень), "ref": план["ref"], "база": план["база"], "готов": False, "постановка": None, "наблюдения": {}}
        def допуск(состояние):
            запись = сам._прочитать(состояние, ключ)
            требовать(запись["план"] == план, "Подменено намерение пакета")
            if not запись["готов"]:
                вход.проверить_открытый_журнал(сам.корень, пакет["запрос"])
                отчёт = вход.обработка.прочитать_файл(сам.корень / Path(пакет["запрос"]).with_name("отчёт.md")).decode("utf-8")
                требовать("состояние=закрыт" not in отчёт, "Закрытый отчёт не возобновляется")
        сам.хранилище.применить_файлы(ключ, "материалы назначений", план["файлы"], ожидаемые_байты={имя: None for имя in план["файлы"]}, ожидаемая_ветка=план["ref"], ожидаемая_база=план["база"], проверить_допуск=допуск)
        with сам.хранилище.изменить() as состояние:
            сам._прочитать(состояние, ключ)["готов"] = True
        return {"пакет": ключ, "назначения": план["назначения"], "sha256": план["sha256"]}

    def закрепить(сам, ключ, коммит, ветка):
        with сам.хранилище.изменить() as состояние:
            запись = сам._прочитать(состояние, ключ)
            требовать(запись["готов"], "Не завершена подготовка пакета")
            прежняя = запись["постановка"]
            требовать(прежняя is None or (прежняя["коммит"], прежняя["ветка"]) == (коммит, ветка), "Коммит запуска уже неизменно закреплён")
            сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемая_ветка=ветка, ожидаемый_коммит=коммит)
            требовать(ветка == запись["ref"], "Подменена собственная ветка запуска")
            гит(сам.корень, "merge-base", "--is-ancestor", запись["база"], коммит)
            файлы = {**запись["план"]["входы_запуска"], **{имя: hashlib.sha256(данные.encode()).hexdigest() for имя, данные in запись["план"]["файлы"].items()}}
            запрос = запись["смысл"]["запрос"]
            for имя in (запрос, str(Path(запрос).with_name("отчёт.md")), прежний.ПУТЬ_РЕЕСТРА, "Планирование/карточки-шагов/README.md", "Требования/README.md"):
                путь = вход.обработка.локальный_путь(сам.корень, имя)
                файлы[имя] = hashlib.sha256(вход.обработка.прочитать_файл(путь)).hexdigest()
            кандидат = {"коммит": коммит, "ветка": ветка, "файлы": файлы}
            постановка.проверить_постановку(сам.корень, кандидат)
            прежний.проверить_инструменты(сам.корень, коммит)
            требовать(hashlib.sha256(Path(__file__).read_bytes()).hexdigest() == ХЭШ_МОДУЛЯ, "Модуль назначений изменён после загрузки")
            прежний.проверить_планирование(сам.корень)
            проверить_источники(сам.корень, запись["смысл"], состояние)
            требовать(прежняя is None or прежняя == кандидат, "Изменён манифест прежнего запуска")
            запись["постановка"] = кандидат
            return copy.deepcopy(кандидат)

    def _аргументы(сам, запись, направление):
        часть = next((часть for часть in запись["смысл"]["назначения"] if часть["направление"] == направление), None)
        требовать(часть is not None and запись["постановка"] is not None, "Нет закреплённого назначения")
        коммит = запись["постановка"]["коммит"]
        материал = str(Path(запись["смысл"]["запрос"]).parent / "материалы/назначения" / (направление + ".json"))
        поручение = часть["задача"]["поручение"] + "\n\nПредметная постановка: " + материал + "; коммит запуска " + коммит + ". Исходный исторический коммит " + часть["исходная_постановка"]["коммит"] + ".\nОбъём: " + часть["объём"] + ". Ограничения: " + часть["ограничения"] + "\n"
        поручение += ("До первой содержательной записи, включая Журнал, прочитай маршрут и проверь собственный физический корень, HEAD и полный ref. При чистом detached HEAD на коммите запуска создай свободную собственную ветку codex/... от того же OID; чужие ветки не перемещай. После повторной проверки чистоты выполни python3 -B Инструменты/fum-reyestr-planirovaniya/scripts/принять-направление.py --корень-репозитория . --задача <свой настоящий UUID> подтвердить-начало --источник <свой первичный JSONL> --коммит " + коммит + ". При несовпадении останови запись и сообщи наблюдение. Затем выполни поручение, проверки и содержательный коммит по правилам своей задачи; обычный push своей ветки разрешён.\n")
        return {"model": "gpt-6-astra", "thinking": "ultra", "title": часть["задача"]["title"], "prompt": поручение, "target": {"type": "project", "projectId": часть["задача"]["projectId"], "environment": {"type": "worktree", "startingState": {"type": "branch", "branchName": запись["постановка"]["ветка"]}}}}

    def допустить(сам, пакет, направление):
        ключ = ключ_пакета(пакет)
        состояние = сам.хранилище.прочитать()
        запись = сам._прочитать(состояние, ключ)
        требовать(смысл(пакет) == запись["смысл"], "Изменён смысл принятого пакета")
        аргументы = сам._аргументы(запись, направление)
        событие = запись["план"]["назначения"][направление]
        def допуск(состояние):
            текущая = сам._прочитать(состояние, ключ)
            требовать(сам._план(пакет, состояние) == текущая["план"] and текущая["готов"], "Изменён полный пакет перед вызовом")
            требовать(аргументы == сам._аргументы(текущая, направление), "Изменены аргументы вызова")
            постановка.проверить_постановку(сам.корень, текущая["постановка"])
            прежний.проверить_инструменты(сам.корень, текущая["постановка"]["коммит"])
            требовать(hashlib.sha256(Path(__file__).read_bytes()).hexdigest() == ХЭШ_МОДУЛЯ, "Модуль назначений изменён после загрузки")
            сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемая_ветка=текущая["ref"], ожидаемый_коммит=текущая["постановка"]["коммит"])
        попытка = сам.хранилище.начать_попытку(событие, аргументы, проверить_допуск=допуск)
        return {**попытка, "пакет": ключ, "событие": событие, "направление": направление, "операция": "создать"}

    def сохранить(сам, ключ, направление, попытка, ответ):
        запись = сам._прочитать(сам.хранилище.прочитать(), ключ)
        требовать(направление in запись["план"]["назначения"], "Неизвестное назначение")
        return сам.хранилище.сохранить_ответ(запись["план"]["назначения"][направление], попытка, извлечь_ответ(ответ))

    def наблюдать(сам, ключ, направление, корень_задачи, задача, источник):
        with сам.хранилище.изменить() as состояние:
            запись = сам._прочитать(состояние, ключ)
            сам.хранилище.проверить_владельца_под_замком(состояние)
            требовать(направление in запись["план"]["назначения"], "Неизвестное назначение")
            попытка = состояние["попытки"].get(запись["план"]["назначения"][направление])
            требовать(попытка is not None and запись["постановка"] is not None, "Нет попытки создания")
            ответ = попытка["ответ"] or {}
            требовать(not ответ.get("противоречивые_идентификаторы") and ответ.get("threadId") in (None, задача), "Раннее наблюдение противоречит полному MCP-ответу")
            граница = постановка.проверить_нативное_поручение(источник, сам.задача, попытка["аргументы"]["prompt"])
            результат = {**постановка.прочитать_подтверждение(Path(корень_задачи), задача, запись["постановка"]["коммит"], источник), "поручение": граница}
            прежнее = запись["наблюдения"].get(направление)
            требовать(прежнее is None or прежнее == результат, "Назначение уже связано с другой задачей")
            требовать(all(другой == направление or значение["задача"] != задача for другой, значение in запись["наблюдения"].items()), "Одна задача не подтверждает два назначения")
            запись["наблюдения"][направление] = результат
            return copy.deepcopy(результат)

def загрузить_связность():
    имя = "связность_для_доставки"
    if имя not in sys.modules:
        описание = importlib.util.spec_from_file_location(имя, ИНСТРУМЕНТЫ / "fum-svyaznostj-rabochej-sessii/scripts/check-session-coherence.py")
        модуль = importlib.util.module_from_spec(описание)
        sys.modules[имя] = модуль
        описание.loader.exec_module(модуль)
    return sys.modules[имя]


def отпечаток(путь):
    безопасный_путь(путь)
    сведения = путь.lstat()
    требовать(stat.S_ISREG(сведения.st_mode), "Служебный путь должен быть обычным файлом")
    return {"режим": сведения.st_mode, "sha256": hashlib.sha256(путь.read_bytes()).hexdigest()}


def дерево(корень, объект):
    итог = {}
    for строка in выполнить(корень, "ls-tree", "-r", "-z", объект).stdout.split(b"\0"):
        if строка:
            сведения, имя = строка.split(b"\t", 1)
            режим, _, оид = сведения.decode().split()
            итог[имя.decode()] = {"режим": режим, "объект": оид}
    return итог


def файлы(корень):
    итог = защищённые_файлы(корень)
    for строка in выполнить(корень, "ls-files", "--stage", "-z").stdout.split(b"\0"):
        if строка:
            сведения, имя = строка.split(b"\t", 1)
            if not сведения.startswith(b"160000 "):
                итог[имя.decode()] = отпечаток(корень / имя.decode())
            elif (корень / имя.decode() / ".git").exists():
                for вложенное, значение in файлы(корень / имя.decode()).items():
                    итог[имя.decode() + "/" + вложенное] = значение
    return итог


def история(корень, запрос, *, пустой=False):
    try:
        return _история(корень, запрос, пустой=пустой)
    except отчёты.ОшибкаОтчёта as ошибка:
        raise ОшибкаПриёма(str(ошибка)) from ошибка


def _история(корень, запрос, *, пустой):
    _, _, путь, каталог, сессия = отчёты.разрешить_сессию(корень, запрос)
    with отчёты.межпроцессная_блокировка(корень, сессия):
        отчёты.запретить_действие_при_возобновлении(каталог, "доставка")
        требовать(not (каталог / отчёты.ИМЯ_СНИМКА).exists(), "Доставке нужен открытый отчёт")
        записи = [] if пустой and (not каталог.exists() or not any(каталог.iterdir())) else отчёты.прочитать_историю_проверок(каталог, сессия)
        требовать(all(запись["состояние"] == "завершён" for _, запись, _ in записи), "Есть незавершённая проверка")
        требовать(отчёты.границы_управляемого_блока(путь.read_text())[2] == отчёты.ОТКРЫТЫЙ_МАРКЕР, "Нужен открытый marker")
    return путь, каталог, сессия, записи


def подготовить(корень, запрос, задача, дерево_слияния, команда, тайм_аут, *, контрольная_точка=None, данные=None):
    путь, каталог, сессия, записи = история(корень, запрос, пустой=True)
    корневая, ошибки = загрузить_связность().codex_thread_id_from_request((корень / сессия).read_text())
    требовать(not ошибки and корневая == задача, "Запрос относится к другой корневой задаче")
    точка = None if контрольная_точка is None else подготовить_точку(корень, контрольная_точка, данные, запрос, задача)
    состав = дерево(корень, дерево_слияния)
    имена = [сессия, str(путь.relative_to(корень)), *(str(имя.relative_to(корень)) for имя, _, _ in записи)]
    требовать(точка is not None or all(имя in состав for имя in имена), "Запрос, отчёт и прежние записи должны входить в дерево слияния")
    идентификатор = str(uuid.uuid4()) if точка is None else контрольная_точка['запуск']['идентификатор']
    запуск = [sys.executable, "-B", str(Path(отчёты.__file__).resolve()), "запустить", "--корень-репозитория", str(корень),
              "--запрос", сессия, "--название", "Проверка обратной доставки", "--исполнитель", "Владелец доставки",
              "--идентификатор-запуска", идентификатор, "--класс-проверки", "адресная",
              "--тайм-аут-секунды", str(тайм_аут), "--", *команда]
    if точка is not None:
        запуск.insert(запуск.index('--тайм-аут-секунды'), '--приёмочные-раунды')
        точка['проверка'] = {'команда': команда, 'тайм_аут': тайм_аут}
    результат = {"запрос": сессия, "корневая_задача": задача, "дерево_слияния": дерево_слияния,
            "отчёт": str(путь.relative_to(корень)), "исходный_отчёт": путь.read_bytes().decode(),
            "файлы": файлы(корень), "прежние": [str(имя.relative_to(корень)) for имя, _, _ in записи],
            "запуск": идентификатор, "команда": запуск, "разница": None}
    if точка is not None:
        результат["точка"] = точка
    return результат


def сверить(корень, граница, *, предпросмотр=False, итоговый=False):
    путь, каталог, сессия, записи = история(корень, граница["запрос"])
    новые = [(имя, запись) for имя, запись, _ in записи if str(имя.relative_to(корень)) not in граница["прежние"]]
    требовать(len(новые) == 1 and новые[0][1]["идентификатор"] == граница["запуск"], "Нет единственного назначенного терминала")
    имя_запуска = str(новые[0][0].relative_to(корень))
    if 'точка' in граница:
        требовать(имя_запуска == граница['точка']['роли']['RAW']
            and отпечаток(корень / имя_запуска)['режим'] == (stat.S_IFREG | 0o644), 'Неверный штатный режим RAW')
    разрешены = {граница["отчёт"], имя_запуска}
    текущие = файлы(корень)
    требовать(set(текущие) == set(граница["файлы"]) | {имя_запуска}, "Появились или исчезли посторонние файлы")
    требовать(all(текущие[имя] == значение for имя, значение in граница["файлы"].items() if имя not in разрешены), "Изменились байты вне служебной разницы")
    требовать(текущие[граница["отчёт"]]["режим"] == граница["файлы"][граница["отчёт"]]["режим"], "Изменился режим отчёта")
    разница = {**граница.get("точка", {}).get("добавления", {}),
               **{имя: отпечаток(корень / имя) for имя in sorted(разрешены)}}
    if итоговый:
        требовать(разница == граница["разница"], "Коммит содержит другие служебные байты")
        return разница, новые[0][1]
    контекст, содержимое = отчёты.текущий_контекст_проверок(корень, сессия, записи)
    ожидаемое = отчёты.заменить_управляемый_блок_в_байтах(граница["исходный_отчёт"].encode(),
        отчёты.сформировать_блок_истории(записи, отчёты.ОТКРЫТЫЙ_МАРКЕР, контекст, содержимое))
    if предпросмотр:
        требовать(путь.read_bytes() in (граница["исходный_отчёт"].encode(), ожидаемое), "Отчёт изменён вне штатного renderer")
        отчёты.выполнить_предпросмотр(корень, Path(сессия))
    требовать(путь.read_bytes() == ожидаемое, "Отчёт не равен точному штатному renderer")
    разница = {**граница.get("точка", {}).get("добавления", {}),
               **{имя: отпечаток(корень / имя) for имя in sorted(разрешены)}}
    требовать(граница["разница"] in (None, разница), "Изменились принятые служебные байты")
    return разница, новые[0][1]


def сверить_дерево(корень, граница, итоговое):
    ожидаемое = дерево(корень, граница["дерево_слияния"])
    for имя, сведения in граница["разница"].items():
        ожидаемое[имя] = {"режим": "100755" if сведения["режим"] & 0o111 else "100644",
                            "объект": гит(корень, "hash-object", "--no-filters", "--", имя)}
    требовать(дерево(корень, итоговое) == ожидаемое, "Индекс не равен слиянию плюс принятой служебной разнице")


def закреплённый_json(ссылка):
    """Физический приватный вход: точные поля, байты, SHA и отсутствие Git-предка."""
    from приём_направления import поля, разобрать
    поля(ссылка, {'путь', 'sha256'})
    путь = Path(ссылка['путь'])
    требовать(путь.is_absolute() and путь == путь.resolve(), 'Нужен физический путь входа')
    безопасный_путь(путь)
    требовать(not any(os.path.lexists(п / '.git') or ((п / 'objects').is_dir() and (п / 'HEAD').is_file())
        for п in путь.parents), 'Вход должен быть вне Git')
    требовать(выполнить(путь.parent, 'rev-parse', '--git-dir', допустимые=(0, 128)).returncode != 0,
        'Вход должен быть вне Git')
    сведения = путь.stat()
    родитель = путь.parent.stat()
    требовать(сведения.st_uid == родитель.st_uid == os.getuid() and родитель.st_mode & 0o077 == 0,
              'Нужны собственные приватные вход и каталог')
    требовать(stat.S_ISREG(сведения.st_mode) and сведения.st_size <= 4 * 1024 * 1024
              and сведения.st_mode & 0o077 == 0, 'Вход должен быть ограниченным приватным файлом')
    сырые = путь.read_bytes()
    требовать(hashlib.sha256(сырые).hexdigest() == ссылка['sha256'], 'Изменился закреплённый вход')
    return разобрать(сырые)


def слияние_генератора(корень, доказательство, писатель):
    """Только чтение завершённого apply; не создаёт и не восстанавливает квитанцию."""
    from приём_направления import поля, хэш, разобрать
    from доставка_план import проверить_план, принять_источник
    from доставка_гит import служебные_состояния, поддержанное_дерево
    поля(доказательство, {'план', 'квитанция'})
    план = проверить_план(закреплённый_json(доказательство['план']))
    конверт = закреплённый_json(доказательство['квитанция'])
    поля(конверт, {'данные', 'sha256'})
    данные = конверт['данные']
    from доставка_состояние import проверить_форму
    проверить_форму(данные)
    требовать(хэш(данные) == конверт['sha256'] and данные['план'] == план['идентификатор'], 'Чужая квитанция apply')
    каталог = Path(доказательство['квитанция']['путь']).parent
    for имя in ('активная.json', 'получатель.json'):
        безопасный_путь(каталог / имя)
    требовать(Path(доказательство['квитанция']['путь']).name == 'квитанция-' + данные['план'] + '.json'
              and разобрать((каталог / 'активная.json').read_bytes()) == {'идентификатор': данные['план']}
              and разобрать((каталог / 'получатель.json').read_bytes()) == {'корень': str(корень), 'начато': True}, 'Нет активной привязки доставки')
    требовать(данные['корень'] == str(корень) and данные['владелец'] == писатель
              and данные['ref'] == гит(корень, 'symbolic-ref', 'HEAD')
              and данные['стадия'] == 'применено' and данные.get('отчёт') is None, 'Нужна собственная применённая доставка')
    источник = {к: план['источник'][к] for к in ('корень', 'ref', 'коммит', 'владелец', 'срез', 'приёмка')}
    требовать(принять_источник(источник, план.get('назначение')) == план['источник'], 'Сдвинулся принятый источник')
    требовать(данные['источник'] == источник['срез'] and any(
        ц['корень'] == str(корень) and ц['коммит'] == данные['до'] and ц['владелец'] == писатель
        and ц['ref'] == данные['ref'] for ц in план['получатели']), 'Подменён получатель плана')
    требовать(служебные_состояния(корень) == ['MERGE_HEAD']
              and гит(корень, 'rev-parse', 'HEAD') == данные['до']
              and гит(корень, 'rev-parse', 'ORIG_HEAD') == данные['до']
              and гит(корень, 'rev-parse', 'MERGE_HEAD') == данные['источник']
              and not гит(корень, 'ls-files', '-u')
              and гит(корень, 'write-tree') == данные['дерево'], 'Дрейф слияния или индекса')
    поддержанное_дерево(корень, данные['источник'])
    текущие = защищённые_файлы(корень)
    требовать(all(текущие.get(и) == с for и, с in данные['защищённые'].items()), 'Изменены защищённые файлы apply')
    return [данные['до'], данные['источник']]


def проверить_точку(корень, манифест, данные, *, новый_эффект=True):
    """Роли выводятся из .9 и независимого ACT, список файлов от вызывающего не принимается."""
    from приём_направления import поля
    sys.path.insert(0, str(ИНСТРУМЕНТЫ / 'fum-svyaznostj-rabochej-sessii/scripts'))
    import создание_коммита as создатель
    поля(манифест, {'схема', 'подготовка', 'поручение', 'запуск'})
    требовать(манифест['схема'] == 'fum.контрольная-точка-обратной-доставки.1', 'Неизвестный служебный manifest')
    выбор = закреплённый_json(манифест['поручение'])
    сохранённая = закреплённый_json(манифест['подготовка'])
    требовать(сохранённая['схема'] == 'fum.подготовленный-коммит.9', 'Нужна обычная подготовка .9')
    подготовка, п = создатель.прочитать_подготовку_готовности(Path(манифест['подготовка']['путь']),
        доверенное_поручение=выбор, новый_эффект=новый_эффект)
    требовать(подготовка == сохранённая and п['исполнитель'] == данные['владелец']
              and п['корень'] == str(корень) and п['ветка'] == данные['ref']
              and п['родители'] == [данные['до'], данные['источник']]
              and п['исходный_коммит'] == данные['до'], 'Подготовка относится к другому слиянию')
    создатель.команды(п)
    требовать(hashlib.sha256((корень / п['история_модели']).read_bytes()).hexdigest()
              == подготовка['история_sha256'], 'Изменилась история модели .9')
    папка = Path(п['запрос']).parent
    требовать(len(папка.parts) == 2 and папка.parts[0] == 'Журнал'
              and п['история_модели'] == (папка / 'материалы/история-модели.json').as_posix(), 'Необычная роль Журнала или модели')
    поля(манифест['запуск'], {'порядок', 'идентификатор'})
    з = манифест['запуск']
    требовать(type(з['порядок']) is int and з['порядок'] == 1
              and str(uuid.UUID(з['идентификатор'])) == з['идентификатор'], 'Новая пара требует первый точный UUID')
    роли = {'запрос': п['запрос'], 'отчёт': (папка / 'отчёт.md').as_posix(), 'модель': п['история_модели'],
            'RAW': (папка / 'материалы/запуски-проверок' / ('1_' + з['идентификатор'] + '.json')).as_posix()}
    требовать(set(роли.values()) <= set(п['разрешённые_цели']), 'Служебные роли вне конечного состава .7')
    return п, роли


def _базовые_файлы(корень, объект, префикс=''):
    # Один проверяемый пакет вместо отдельного процесса на каждый blob.
    # Не кэшируем изменяемые файлы, индекс, ACT или нативное происхождение.
    from обычное_поручение import история as гит_объекты
    состав = дерево(корень, объект)
    объекты = гит_объекты.прочитать_объекты(корень,
        [з['объект'] for з in состав.values() if з['режим'] != '160000'], 'blob')
    итог = {}
    for имя, запись in состав.items():
        if запись['режим'] == '160000':
            итог.update(_базовые_файлы(корень / имя, запись['объект'], префикс + имя + '/'))
        else:
            сырые = объекты[запись['объект']]
            итог[префикс + имя] = {'режим': stat.S_IFREG | (int(запись['режим'], 8) & 0o777),
                                   'sha256': hashlib.sha256(сырые).hexdigest()}
    return итог


def подготовить_точку(корень, манифест, данные, запрос, задача):
    п, роли = проверить_точку(корень, манифест, данные)
    требовать(п['запрос'] == запрос and п['задача'] == задача, 'Чужой отчёт контрольной точки')
    база = _базовые_файлы(корень, данные['дерево'])
    требовать(not set(роли.values()) & (set(база) | set(данные['защищённые'])), 'Новая служебная роль пересекает сохранённые файлы')
    навигация = проверить_навигацию(корень, данные['дерево'], роли['запрос'])
    разрешены = {роли['запрос'], роли['отчёт'], роли['модель'], *навигация}
    требовать(разрешены <= set(п['разрешённые_цели']), 'Навигация вне области .7/ACT')
    текущие = файлы(корень)
    требовать(set(текущие) == set(база) | set(данные['защищённые']) | разрешены, 'Посторонний файл вне типизированных ролей')
    требовать(all(текущие[и] == с for и, с in {**база, **данные['защищённые']}.items() if и not in навигация), 'Изменены исходные или защищённые байты/режимы')
    требовать(all(текущие[и]['режим'] == (stat.S_IFREG | (0o600 if и == роли['модель'] else 0o644)) for и in разрешены), 'Неверный штатный режим служебной роли')
    добавления = {и: текущие[и] for и in sorted(разрешены)}
    исходный_индекс = гит(корень, 'write-tree')
    сверить_дерево(корень, {'дерево_слияния': данные['дерево'], 'разница': добавления}, исходный_индекс)
    return {'манифест': манифест, 'роли': роли, 'добавления': добавления,
            'индекс_до_проверки': исходный_индекс}


def проверить_навигацию(корень, объект, запрос):
    """Только штатные тела соседних ссылок и двух производных индексов."""
    sys.path.insert(0, str(ИНСТРУМЕНТЫ / 'fum-svyaznostj-rabochej-sessii/scripts'))
    import подготовка_этапа_коммита as этап

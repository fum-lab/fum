def видимые_строки(текст):
    """Дословные ограждённые блоки остаются данными, включая похожие метки."""
    ограда = None
    строки = []
    for строка in текст.splitlines():
        найденная = re.match(r'^ {0,3}(`{3,}|\x7e{3,})(.*)$', строка)
        if ограда is not None:
            if найденная and найденная[1][0] == ограда[0] and len(найденная[1]) >= len(ограда) and not найденная[2].strip():
                ограда = None
            continue
        if найденная:
            ограда = найденная[1]
        elif not строка.startswith(('    ', '\t')):
            строки.append(строка)
    контракт.требовать(ограда is None, 'незакрытый дословный блок')
    return '\n'.join(строки)


def _свойства(текст):
    видимое = видимые_строки(текст)
    метки = re.findall(r'^<!-- FUM-ОБЫЧНЫЙ-ЖУРНАЛ: (.*?) -->$', видимое, re.M)
    if not метки:
        контракт.требовать('FUM-ОБЫЧНЫЙ-ЖУРНАЛ:' not in видимое, 'скрытое поколение пары')
        return None
    контракт.требовать(метки == ['1'] and видимое.count('FUM-ОБЫЧНЫЙ-ЖУРНАЛ:') == 1,
        'неизвестное или повторное поколение пары')
    значения = re.findall(r'^<!-- FUM-ОБЫЧНЫЙ-ЭТАП: (.*?) -->$', видимое, re.M)
    контракт.требовать(len(значения) == 1, 'нет единственного происхождения этапа')
    данные = _разобрать_данные(значения[0])
    контракт.поля(данные, {'журнал', 'задача', 'писатель', 'основание', 'этап'})
    контракт.идентичность(данные['задача']); контракт.идентичность(данные['писатель'])
    контракт.селектор(данные['основание']); контракт.отпечаток(данные['этап'])
    контракт.имя_журнала(данные['журнал'])
    контракт.требовать(значения[0].encode() == контракт.канон(данные), 'неканоническое происхождение')
    строки = текст.splitlines()
    контракт.требовать(текст.startswith('# ') and len(строки) >= 4 and строки[1] == ''
        and строки[2] == МАРКЕР and строки[3] == '<!-- FUM-ОБЫЧНЫЙ-ЭТАП: ' + значения[0] + ' -->',
        'скрытый маркер рабочего формата')
    return данные



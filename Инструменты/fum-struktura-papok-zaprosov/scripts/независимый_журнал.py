def преобразовать_каркас(файлы, журнал, задача, команды, писатель, основание):
    # Прежний renderer и шаблоны остаются неизменными. Преобразуется только
    # новый результат самостоятельной версией; повтор P.1 его не использует.
    данные = {'журнал': журнал, 'задача': задача, 'писатель': писатель, 'основание': основание}
    данные['этап'] = контракт.хэш(контракт.канон({**данные, 'команды': команды}))
    метаданные = МАРКЕР + '\n<!-- FUM-ОБЫЧНЫЙ-ЭТАП: ' + контракт.канон(данные).decode() + ' -->\n'
    новые = []
    for файл in файлы:
        исходные = файл.data
        if файл.path.name == 'отчёт.md':
            # Полный существующий набор управляемых границ устанавливается
            # до метаданных. Обычный filler меняет итог внутри его блока,
            # сохраняя происхождение перед ним без изменения старого filler.
            import блоки_карточки as блоки
            исходные = блоки._поставить_границы(исходные, блоки._положение(исходные, отчёт=True))
        текст = исходные.decode()
        первая, хвост = текст.split('\n\n', 1)
        текст = первая + '\n\n' + метаданные + '\n' + хвост
        if файл.path.name == 'запрос.md':
            текст = re.sub(r'(?ms)^## Навигация по запросам\n.*?(?=^## )',
                '## Навигация по запросам\n\n'
                'Собственная открытая пара; хронологические связи принятого состава '
                'проверяются в отдельном индексе Журнала.\n\n', текст, count=1)
        новые.append(каркас.PreparedFile(файл.path, текст.encode(), файл.mode))
    план = {'схема': СХЕМА_ПЛАНА, **данные, 'файлы': [
        {'путь': ф.path.as_posix(), 'sha256': контракт.хэш(ф.data), 'режим': ф.mode}
        for ф in новые], 'разрешение_установки': False}
    return новые, план


def установить_пару(корень, файлы, план):
    """Точная файловая операция после внешнего допуска; не выдаёт ACT или READY."""
    _ресурсы()
    контракт.поля(план, {'схема', 'журнал', 'задача', 'писатель', 'основание',
        'этап', 'файлы', 'разрешение_установки'})
    контракт.требовать(план['схема'] == СХЕМА_ПЛАНА and план['разрешение_установки'] is False,
        'неверное поколение установки')
    контракт.требовать(os.environ.get('CODEX_THREAD_ID') == план['писатель'], 'чужой писатель пары')
    ожидаемые = ['Журнал/' + план['журнал'] + '/' + имя for имя in ('запрос.md', 'отчёт.md')]
    контракт.требовать(len(файлы) == 2 and [ф.path.as_posix() for ф in файлы] == ожидаемые,
        'установка вышла из собственной пары')
    свойства = {к: план[к] for к in ('журнал', 'задача', 'писатель', 'основание', 'этап')}
    контракт.требовать(план['файлы'] == [{'путь': ф.path.as_posix(),
        'sha256': контракт.хэш(ф.data), 'режим': ф.mode} for ф in файлы]
        and all(ф.mode == 0o644 and _свойства(ф.data.decode()) == свойства for ф in файлы),
        'подменены байты или идентичность плана')
    корень = физический_корень(корень)
    # Проверка исходного написания предшествует любому разрешению alias.
    точный_путь(корень, ожидаемые[0])
    for имя in ожидаемые:
        точный_путь(корень, имя)
    существующие = [os.path.lexists(корень / ф.path) for ф in файлы]
    if any(существующие):
        контракт.требовать(all(существующие) and all((корень / ф.path).is_file()
            and (корень / ф.path).read_bytes() == ф.data
            and stat.S_IMODE((корень / ф.path).stat().st_mode) == ф.mode for ф in файлы),
            'неизвестный остаток или конфликт установки')
        return {'повтор': True}
    контракт.требовать(not os.path.lexists(корень / 'Журнал' / план['журнал']),
        'неизвестный остаток папки до установки пары')
    каркас._apply_prepared_transaction(корень, файлы)
    return {'повтор': False}


def _проверить_структуру(записи):
    """Полный управляемый инвентарь проверяется до выделения файлов пары."""
    ключи = {}
    непустые_материалы = set()
    for имя, (_, тип, _) in записи.items():
        части = PurePosixPath(имя).parts
        if тип == 'blob' and len(части) > 3 and части[0] == 'Журнал' and части[2] == 'материалы':
            непустые_материалы.update('/'.join(части[:н]) for н in range(3, len(части)))
    for имя, (режим, тип, идентификатор_объекта) in записи.items():
        части = PurePosixPath(имя).parts
        for номер, часть in enumerate(части):
            родитель = '/'.join(части[:номер])
            ключ = (родитель, контракт.ключ_коллизии(часть))
            if номер == 0 or части[0] in {'Журнал', 'Индексы'}:
                контракт.требовать(ключ not in ключи or ключи[ключ] == часть,
                    'коллизия компонента управляемой области')
                ключи[ключ] = часть
        if контракт.ключ_коллизии(части[0]) in {'журнал', 'индексы'}:
            контракт.требовать(части[0] in {'Журнал', 'Индексы'}, 'неверный регистр управляемого корня')
        if части[0] != 'Журнал': continue
        контракт.требовать(тип in {'tree', 'blob'} and режим in {'040000', '100644', '100755'},
            'необычный тип управляемой записи Журнала')
        if len(части) == 1:
            контракт.требовать(тип == 'tree', 'корень Журнала не является деревом')
        elif len(части) == 2:
            if части[1] == 'README.md':
                контракт.требовать(тип == 'blob' and режим == '100644', 'необычный README Журнала')
            else:
                контракт.имя_журнала(части[1], прежнее=True)
                контракт.требовать(тип == 'tree' and '/'.join(('Журнал', части[1], 'запрос.md')) in записи,
                    'пустая или посторонняя папка Журнала')
        elif len(части) == 3:
            контракт.требовать(части[2] in {'запрос.md', 'отчёт.md', 'материалы'},
                'посторонний ребёнок папки Журнала')
            контракт.требовать((тип == 'tree') if части[2] == 'материалы'
                else (тип == 'blob' and режим == '100644'), 'необычный файл пары или материалы')
        else:
            контракт.требовать(части[2] == 'материалы', 'вложенная запись вне материалов')
            контракт.требовать(тип != 'tree' or имя in непустые_материалы,
                'неизвестный пустой вложенный каталог материалов')
    контракт.требовать('Журнал/README.md' in записи, 'нет README полного Журнала')


def _дерево_коммита(корень, коммит):
    записи = {}
    for строка in _гит(корень, 'ls-tree', '-r', '-t', '-z', '--full-tree', коммит).split(b'\0'):
        if not строка: continue
        заголовок, имя = строка.split(b'\t', 1)
        режим, тип, идентификатор_объекта = заголовок.decode().split()
        имя = имя.decode(); контракт.путь(имя)
        контракт.требовать(имя not in записи, 'повтор пути Git-дерева')
        записи[имя] = (режим, тип, идентификатор_объекта)
    _проверить_структуру(записи)
    return записи


def _живое_дерево(корень, *, индекс=None):
    точный_путь(корень, 'Журнал/README.md', существует=True, индекс=индекс)
    записи = {'Журнал': ('040000', 'tree', None)}
    # Верхний инвентарь также видит двойника корня, даже если он пуст.
    for файл in корень.iterdir():
        записи.setdefault(файл.name, ('040000', 'tree', None) if файл.is_dir() else ('100644', 'blob', None))
    for родитель, каталоги, файлы in os.walk(корень / 'Журнал', followlinks=False):
        for имя in каталоги + файлы:
            файл = Path(родитель) / имя; путь = файл.relative_to(корень).as_posix()
            контракт.требовать(not файл.is_symlink(), 'символическая запись Журнала')
            с = файл.lstat()
            контракт.требовать(stat.S_ISDIR(с.st_mode) or stat.S_ISREG(с.st_mode), 'необычная живая запись Журнала')
            режим = '040000' if stat.S_ISDIR(с.st_mode) else ('100755' if с.st_mode & 0o111 else '100644')
            записи[путь] = (режим, 'tree' if stat.S_ISDIR(с.st_mode) else 'blob', None)
    _проверить_структуру(записи)
    return записи


def _файлы_коммита(корень, коммит):
    контракт.требовать(type(коммит) is str and re.fullmatch('[0-9a-f]{40}|[0-9a-f]{64}', коммит),
        'нужен полный коммит принятого состава')
    контракт.требовать(_гит(корень, 'cat-file', '-t', коммит) == b'commit\n', 'нужен коммит')
    дерево = {}
    for путь, (режим, тип, идентификатор) in _дерево_коммита(корень, коммит).items():
        if len(PurePosixPath(путь).parts) == 3 and PurePosixPath(путь).name in {'запрос.md', 'отчёт.md'}:
            if PurePosixPath(путь).parts[0] != 'Журнал': continue
            контракт.требовать(тип == 'blob' and режим == '100644', 'необычный принятый файл пары Журнала')
            дерево[путь] = идентификатор
    return _прочитать_объекты(корень, дерево)


def _прочитать_объекты(корень, дерево):
    """Читает точные blob OID одним пакетом и независимо сверяет каждый объект."""
    имена = list(дерево)
    идентификаторы = list(dict.fromkeys(дерево[п] for п in имена))
    if not идентификаторы: return {}
    сырой = _гит(корень, 'cat-file', '--batch', вход=('\n'.join(идентификаторы) + '\n').encode())
    объекты = {}; позиция = 0
    for идентификатор in идентификаторы:
        конец = сырой.index(b'\n', позиция)
        поля = сырой[позиция:конец].decode().split()
        контракт.требовать(len(поля) == 3 and поля[:2] == [идентификатор, 'blob'], 'подменён batch Git')
        размер = int(поля[2]); начало = конец + 1
        данные = сырой[начало:начало + размер]
        контракт.требовать(len(данные) == размер and сырой[начало + размер:начало + размер + 1] == b'\n',
            'усечён batch Git')
        алгоритм = hashlib.sha1 if len(идентификатор) == 40 else hashlib.sha256
        контракт.требовать(алгоритм(b'blob ' + str(размер).encode() + b'\0' + данные).hexdigest() == идентификатор,
            'неверный blob OID')
        объекты[идентификатор] = данные; позиция = начало + размер + 1
    контракт.требовать(позиция == len(сырой), 'лишний хвост batch Git')
    return {п: объекты[дерево[п]] for п in имена}


def состав_принятого_дерева(корень, коммит):
    файлы = _файлы_коммита(корень, коммит)
    записи = []; имена = set()
    исторические = _разобрать_данные((СЦЕНАРИИ.parent / 'исторические-одиночные-запросы.json').read_bytes())
    одиночные = {з['путь']: з['sha256'] for з in исторические['записи']}
    for путь in sorted(п for п in файлы if PurePosixPath(п).name == 'запрос.md'):
        папка = PurePosixPath(путь).parent.name
        ключ = контракт.ключ_коллизии(папка)
        контракт.требовать(ключ not in имена, 'коллизия имени принятой записи'); имена.add(ключ)
        запрос = файлы[путь]; текст = запрос.decode(); свойства = _свойства(текст)
        отчёт = str(PurePosixPath(путь).with_name('отчёт.md'))
        части = [путь]
        if отчёт in файлы:
            части.append(отчёт)
            if свойства is not None:
                контракт.требовать(_свойства(файлы[отчёт].decode()) == свойства
                    and свойства['журнал'] == папка, 'смешанная идентичность пары')
                формат = ФОРМАТ; идентификатор = свойства['этап']
            elif 'FUM-ЖУРНАЛ-ФОРМАТ:' in видимые_строки(текст):
                контракт.требовать(re.findall(r'^<!-- FUM-ЖУРНАЛ-ФОРМАТ: (.*?) -->$', видимые_строки(текст), re.M) == ['2'],
                    'неизвестный формат прежней независимой пары')
                формат = 'fum.независимая-пара-журнала.1'
                идентификаторы = re.findall(r'^<!-- FUM-ЭТАП-ID: ([0-9a-f]{64}) -->$', видимые_строки(текст), re.M)
                контракт.требовать(len(идентификаторы) == 1, 'нет идентичности независимой пары')
                идентификатор = идентификаторы[0]
            else:
                формат = 'fum.прежняя-пара-журнала.1'
                идентификатор = контракт.хэш(путь.encode() + b'\0' + запрос)
        else:
            контракт.требовать(свойства is None and одиночные.get(путь) == контракт.хэш(запрос),
                'одиночный запрос не входит в закреплённую историю')
            формат = 'fum.исторический-одиночный-запрос-журнала.1'
            идентификатор = контракт.хэш(путь.encode() + b'\0' + запрос)
        записи.append({'идентификатор': идентификатор, 'формат': формат, 'журнал': папка,
            'заголовок': текст.splitlines()[0][2:], 'файлы': [
                {'путь': имя, 'sha256': контракт.хэш(файлы[имя]), 'режим': 0o644} for имя in части],
            'приёмка': {'коммит': коммит, 'путь': путь, 'sha256': контракт.хэш(запрос)}})
    контракт.требовать(set(файлы) == {ф['путь'] for з in записи for ф in з['файлы']},
        'отчёт без принятого запроса')
    return {'схема': СХЕМА_СОСТАВА, 'коммит': коммит,
        'записи': sorted(записи, key=lambda з: з['журнал'])}


def построить_принятый_индекс(корень, состав):
    контракт.поля(состав, {'схема', 'коммит', 'записи'})
    контракт.требовать(состав['схема'] == СХЕМА_СОСТАВА, 'неизвестное поколение принятого состава')
    полный = состав_принятого_дерева(корень, состав['коммит'])
    контракт.требовать(type(состав['записи']) is list
        and sorted(состав['записи'], key=lambda з: з['журнал']) == полный['записи'],
        'состав не покрывает выбранное Git-дерево точно')
    вход = {'схема': 'fum.состав-независимого-журнала.3', 'записи': полный['записи']}
    ожидаемый = контракт.хэш(контракт.канон(вход))
    return индексы.построить_индекс(вход, _файлы_коммита(корень, состав['коммит']), ожидаемый_sha256=ожидаемый)


def проверить_смешанный(корень, состав, *, открытая=None, допуск_ребёнка=None):
    if допуск_ребёнка is None:
        return _проверить_смешанный_с_навигацией(корень, состав, открытая=открытая)
    import связность_независимого_журнала as связь
    допущено = связь.проверить_допуск_ребёнка(допуск_ребёнка, корень, состав=состав)
    if открытая is not None:
        контракт.требовать(открытая == допущено['параметры']['контракт_журнала']['открытая'],
            'чужая открытая пара проверенного ребёнка')
    результат = _проверить_смешанный_с_навигацией(корень, состав, открытая=открытая,
        навигация_основы=допущено['индексы'][ПУТЬ_ИНДЕКСА])
    связь.проверить_допуск_ребёнка(допуск_ребёнка, корень, состав=состав)
    return результат


def _проверить_смешанный_с_навигацией(корень, состав, *, открытая=None,
        навигация_основы=None):
    корень = физический_корень(корень)
    with ИндексПутей(корень, контракт.ключ_коллизии) as индекс_путей:
        return _проверить_смешанный_проход(
            корень, состав, открытая, индекс_путей,
            навигация_основы=навигация_основы)


def _проверить_смешанный_проход(корень, состав, открытая, индекс_путей, *, навигация_основы=None):
    живое_дерево = _живое_дерево(корень, индекс=индекс_путей)
    каркас._assert_no_symlinks(корень, ('Журнал', 'Индексы'))
    индекс = построить_принятый_индекс(корень, состав)
    файл_индекса = точный_путь(корень, ПУТЬ_ИНДЕКСА, существует=True, индекс=индекс_путей)
    ожидаемая_навигация = индекс['байты'] if навигация_основы is None else навигация_основы
    контракт.требовать(stat.S_IMODE(файл_индекса.stat().st_mode) == 0o644
        and файл_индекса.read_bytes() == ожидаемая_навигация, 'устаревший смешанный индекс или его режим')
    принято = {ф['путь']: ф for з in состав['записи'] for ф in з['файлы']}
    открытые = set()
    if открытая is not None:
        контракт.поля(открытая, {'схема', 'журнал', 'задача', 'писатель', 'основание',
            'этап', 'файлы', 'разрешение_установки'})
        контракт.требовать(открытая.get('схема') == СХЕМА_ПЛАНА, 'неизвестная открытая граница')
        свойства = {к: открытая[к] for к in ('журнал', 'задача', 'писатель', 'основание', 'этап')}
        открытые = {'Журнал/' + открытая['журнал'] + '/' + ч for ч in ('запрос.md', 'отчёт.md')}
        контракт.требовать(not открытые.intersection(принято), 'принятая пара не является открытым хвостом')
        for имя in открытые:
            файл = точный_путь(корень, имя, существует=True, индекс=индекс_путей)
            контракт.требовать(stat.S_IMODE(файл.stat().st_mode) == 0o644
                and _свойства(файл.read_text()) == свойства, 'чужая открытая пара или режим')
    публикуемые = каркас._project_relative_files(корень)
    пары = {п.as_posix() for п in публикуемые if len(п.parts) == 3
        and п.parts[0] == 'Журнал' and п.name in {'запрос.md', 'отчёт.md'}}
    контракт.требовать(пары == set(принято) | открытые, 'пропущенная или посторонняя пара checkout')
    for имя, файл in принято.items():
        путь = точный_путь(корень, имя, существует=True, индекс=индекс_путей)
        контракт.требовать(путь.is_file() and stat.S_IMODE(путь.stat().st_mode) == файл['режим']
            and контракт.хэш(путь.read_bytes()) == файл['sha256'], 'подменены принятые байты или режим')
    # Пара не исчерпывает закрытую запись: её материалы, RAW и вложенные
    # каталоги также принадлежат выбранному H. Фильтр пар их не скрывает.
    дерево = _дерево_коммита(корень, состав['коммит'])
    принятое_дерево = {п: з for п, з in дерево.items()
        if п == 'Журнал/README.md' or п.startswith('Журнал/') and п.count('/') >= 1}
    открытый_префикс = ('Журнал/' + открытая['журнал'] + '/') if открытая else None
    текущие = {п: з for п, з in живое_дерево.items() if п.startswith('Журнал/')
        and not (открытый_префикс and (п == открытый_префикс[:-1] or п.startswith(открытый_префикс)))}
    # P.1 создаёт прямой материалы/ даже без файлов; Git не хранит пустой
    # каталог. Известная форма сохраняется на диске, без вымышленного blob H.
    пустые_материалы = {'/'.join(('Журнал', з['журнал'], 'материалы')) for з in состав['записи']
        if any(Path(ф['путь']).name == 'отчёт.md' for ф in з['файлы'])}
    допустимые_пустые = {п for п in set(текущие) - set(принятое_дерево)
        if п in пустые_материалы and текущие[п][:2] == ('040000', 'tree')
        and not any((корень / п).iterdir())}
    контракт.требовать(set(текущие) - допустимые_пустые == set(принятое_дерево),
        'неполная или посторонняя запись закрытого Журнала')
    данные = _прочитать_объекты(корень, {п: з[2] for п, з in принятое_дерево.items() if з[1] == 'blob'})
    for имя, (режим, тип, _) in принятое_дерево.items():
        контракт.требовать(текущие[имя][:2] == (режим, тип), 'подменён режим принятого материала')
        if тип == 'blob':
            файл = точный_путь(корень, имя, существует=True, индекс=индекс_путей)
            контракт.требовать(файл.read_bytes() == данные[имя], 'подменён принятый материал Журнала')
    прежние = sorted(з['журнал'] for з in состав['записи'] if з['формат'] in {
        'fum.прежняя-пара-журнала.1', 'fum.исторический-одиночный-запрос-журнала.1'})
    for номер, имя in enumerate(прежние):
        файл = корень / 'Журнал' / имя / 'запрос.md'
        каркас._validate_request_header(файл, имя)
        каркас._validate_navigation(корень, файл,
            прежние[номер - 1] if номер else None,
            прежние[номер + 1] if номер + 1 < len(прежние) else None)
    return {'принятых': len(состав['записи']), 'открытых': int(открытая is not None),
        'состав_sha256': индекс['состав_sha256'], 'разрешение_установки': False}

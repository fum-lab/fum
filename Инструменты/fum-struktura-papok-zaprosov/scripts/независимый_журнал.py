def _разобрать_данные(байты):
    def уникальные(пары):
        результат = {}
        for имя, значение in пары:
            контракт.требовать(имя not in результат, 'повтор JSON-ключа')
            результат[имя] = значение
        return результат
    return json.loads(байты, object_pairs_hook=уникальные)


def _гит(корень, *аргументы, вход=None):
    среда = {к: з for к, з in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_NO_REPLACE_OBJECTS='1', GIT_OPTIONAL_LOCKS='0', GIT_NO_LAZY_FETCH='1')
    процесс = subprocess.run(['git', '--no-replace-objects', '--no-optional-locks',
        '-c', 'core.hooksPath=' + os.devnull, '-C', str(корень), *аргументы],
        input=вход, capture_output=True, env=среда, timeout=120)
    контракт.требовать(процесс.returncode == 0, 'недоступный Git-объект Журнала')
    return процесс.stdout


def точный_путь(корень, имя, *, существует=False, индекс=None):
    """Проверяет каждый компонент адреса без обхода посторонних каталогов."""
    корень = Path(корень)
    контракт.требовать(корень.is_absolute() and корень == корень.resolve(), 'нефизический корень')
    контракт.путь(имя)
    текущий = корень
    части = PurePosixPath(имя).parts
    for номер, часть in enumerate(части):
        if текущий.is_dir():
            if индекс is None:
                имена = [п.name for п in текущий.iterdir()]
                совпадения = [и for и in имена if контракт.ключ_коллизии(и) == контракт.ключ_коллизии(часть)]
            else:
                контракт.требовать(индекс.корень == корень, 'чужой индекс прохода')
                совпадения = индекс.совпадения(текущий, часть)
            контракт.требовать(not совпадения or совпадения == [часть], 'регистр или коллизия компонента')
        текущий /= часть
        контракт.требовать(not текущий.is_symlink(), 'символический компонент адреса')
        контракт.требовать(номер == len(части) - 1 or not os.path.lexists(текущий)
            or текущий.is_dir(), 'промежуточный компонент не является каталогом')
    контракт.требовать(not существует or текущий.is_file(), 'нет обычного адресного файла')
    return текущий


def физический_корень(корень):
    корень = Path(корень)
    контракт.требовать(корень.is_absolute() and корень == корень.resolve(), 'нефизический корень')
    текущий = Path(корень.anchor)
    for часть in корень.parts[1:]:
        совпадения = [п.name for п in текущий.iterdir()
            if контракт.ключ_коллизии(п.name) == контракт.ключ_коллизии(часть)]
        контракт.требовать(совпадения == [часть], 'регистр или коллизия предка корня')
        текущий /= часть
        контракт.требовать(not текущий.is_symlink() and текущий.is_dir(), 'необычный предок корня')
    return корень



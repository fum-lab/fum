def _видимые_строки(текст):
    """Дословные ограды и отступы сохраняют данные исходных команд."""
    ограда = None
    строки = []
    for строка in текст.splitlines():
        найденная = re.match(r'^ {0,3}(`{3,}|\x7e{3,})(.*)$', строка)
        if ограда is not None:
            if (найденная and найденная[1][0] == ограда[0]
                    and len(найденная[1]) >= len(ограда) and not найденная[2].strip()):
                ограда = None
            continue
        if найденная:
            ограда = найденная[1]
        elif not строка.startswith(('    ', '\t')):
            строки.append(строка)
    требовать(ограда is None, 'незакрытый дословный блок пары.2')
    return '\n'.join(строки)


def _разобрать_метаданные(сырые):
    def уникальные(пары):
        результат = {}
        for имя, значение in пары:
            требовать(имя not in результат, 'повтор JSON-ключа пары.2')
            результат[имя] = значение
        return результат
    return json.loads(сырые, object_pairs_hook=уникальные)


def разобрать_имя(имя):
    совпадение = ШАБЛОН.fullmatch(имя) if type(имя) is str else None
    требовать(совпадение is not None, 'неверное ASCII-имя обычного Журнала.2')
    требовать(len(имя.encode()) <= 255, 'имя Журнала слишком длинное')
    try:
        datetime.strptime(совпадение['prefix'], '%Y-%m-%d_%H-%M-%S_msk')
    except ValueError as ошибка:
        raise каркас.LayoutError('невозможное время ASCII-Журнала') from ошибка
    return совпадение


def новое_поколение(имя):
    """Поколение задаёт точный временной prefix, а не слово внутри suffix."""
    return type(имя) is str and re.match(r'^[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}-[0-9]{2}-[0-9]{2}_msk_', имя) is not None


def нормализовать(транслитерация):
    # Проверка до lower: Unicode-lookalike не превращается в допустимую букву.
    требовать(type(транслитерация) is str and транслитерация.isascii()
        and re.fullmatch(r'[A-Za-z0-9]+(?:[ -][A-Za-z0-9]+)*', транслитерация) is not None,
        'LinguisticKit не дал допустимое ASCII-имя')
    return транслитерация.lower().replace(' ', '-')


def каталоги_формата():
    """Точный результат ранее учтённого Swift-вызова; никакой ручной таблицы."""
    путь = Path(__file__).resolve().parents[1] / 'каталоги-журнала.2.json'
    сырые = путь.read_bytes()
    требовать(not путь.is_symlink() and hashlib.sha256(сырые).hexdigest() == ПОЛИТИКА_КАТАЛОГОВ_SHA256,
        'изменена вычисленная политика каталогов')
    данные = json.loads(сырые)
    требовать(данные['ревизия'] == РЕВИЗИЯ
        and set(данные['транслитерации']) == set(ИСТОЧНИКИ_КАТАЛОГОВ), 'другая политика каталогов')
    return {ключ: нормализовать(данные['транслитерации'][ключ]) for ключ in ИСТОЧНИКИ_КАТАЛОГОВ}


def каталог_материалов(имя):
    if ШАБЛОН.fullmatch(имя):
        разобрать_имя(имя)
        return каталоги_формата()['материалы']
    каркас._validate_stem(имя, 'legacy journal')
    return 'материалы'


def относительный_каталог_проверок(сессия):
    путь = PurePosixPath(сессия)
    требовать(len(путь.parts) == 3 and путь.parts[0] == 'Журнал' and путь.name == 'запрос.md',
        'неверный путь сессии resolver')
    имя = путь.parts[1]
    if ШАБЛОН.fullmatch(имя):
        разобрать_имя(имя)
        каталоги = каталоги_формата()
        return PurePosixPath(*(каталоги[к] for к in ИСТОЧНИКИ_КАТАЛОГОВ))
    каркас._validate_stem(имя, 'legacy journal')
    return PurePosixPath(*ИСТОЧНИКИ_КАТАЛОГОВ)


def проверить_коллизии(корень, имя):
    разобрать_имя(имя)
    папка = Path(корень) / 'Журнал'
    требовать(not папка.is_symlink() and папка.is_dir(), 'необычный корень Журнала')
    ключ = unicodedata.normalize('NFC', имя).casefold()
    for сосед in папка.iterdir():
        требовать(сосед.name == имя or unicodedata.normalize('NFC', сосед.name).casefold() != ключ,
            'коллизия ASCII-папки Журнала')


def штатно_преобразовать(корень, строки):
    корень = Path(корень)
    требовать(корень.is_absolute() and корень == корень.resolve(), 'нефизический корень имён')
    пакет = корень / 'Инструменты/fum-proverka-nazvanij-avtomatizacij'
    for имя, ожидаемый in РЕСУРСЫ_ПРЕОБРАЗОВАТЕЛЯ.items():
        файл = пакет / имя
        требовать(not файл.is_symlink() and hashlib.sha256(файл.read_bytes()).hexdigest() == ожидаемый,
            'изменён закреплённый преобразователь имён')
    путь = корень / 'Инструменты/fum-bratislavskaya-proyekciya-pamyati/scripts/братиславская_проекция_памяти.py'
    имя_модуля = 'fum_изолированный_преобразователь_имён'
    global ПРОЕКЦИЯ_ИМЁН
    def сверить_посредника():
        загрузка.сверить_загрузку(корень, {путь.relative_to(корень).as_posix(): ПРОЕКЦИЯ_SHA256})
        if ПРОЕКЦИЯ_ИМЁН is not None:
            требовать(sys.modules.get(имя_модуля) is ПРОЕКЦИЯ_ИМЁН
                and ПРОЕКЦИЯ_ИМЁН.__file__ == str(путь)
                and ПРОЕКЦИЯ_ИМЁН.КОД_ПРИ_ЗАГРУЗКЕ == ПРОЕКЦИЯ_SHA256,
                'подменён исполняемый посредник имён')
    сверить_посредника()
    if ПРОЕКЦИЯ_ИМЁН is None:
        требовать(имя_модуля not in sys.modules, 'непроверенный посредник уже загружен')
        ПРОЕКЦИЯ_ИМЁН, отпечаток = загрузка.загрузить_исходник(путь, имя_модуля)
        требовать(отпечаток == ПРОЕКЦИЯ_SHA256, 'изменён источник посредника имён')
    модуль = ПРОЕКЦИЯ_ИМЁН
    сверить_посредника()
    требовать(модуль.РЕВИЗИЯ_ЗАВИСИМОСТИ == РЕВИЗИЯ, 'другая ревизия LinguisticKit')
    # Существующий контур проверяет всё дерево зависимости, разворачивает Git
    # archives вне checkout и сверяет исполнение до/после; кэш также проверяемый.
    with модуль.подготовить_изолированный_преобразователь(корень, использовать_кэш=True) as (команда, проверить):
        сверить_посредника()
        проверить()
        сверить_посредника()
        процесс = subprocess.run(команда, input=json.dumps(строки, ensure_ascii=False).encode(),
            capture_output=True, timeout=120, env=модуль.окружение_инструментария())
        проверить()
        сверить_посредника()
        требовать(процесс.returncode == 0, 'неуспешный штатный преобразователь имён')
        try:
            результат = json.loads(процесс.stdout)
        except (ValueError, UnicodeError) as ошибка:
            raise каркас.LayoutError('неверный JSON преобразователя') from ошибка
        требовать(type(результат) is list and len(результат) == len(строки)
            and all(type(значение) is str for значение in результат), 'неверный массив преобразователя')
    return результат


def построить_имя(корень, имя, источник, заголовок):
    совпадение = разобрать_имя(имя)
    требовать(type(источник) is str and type(заголовок) is str, 'нужны русский sourceLabel и title')
    требовать(len(источник.encode('utf-8')) <= 1024 and len(заголовок.encode('utf-8')) <= 1024,
        'русский sourceLabel или title превышает предел1024 байт')
    каркас._проверить_метку_сессии(источник)
    требовать(заголовок == каркас._заголовок_из_метки(источник), 'title не выведен из русского sourceLabel')
    # Код и закреплённая зависимость принадлежат исполняющему checkout.
    # Целевой корень задаёт namespace пары, но не источник исполняемого кода.
    транслитерации = штатно_преобразовать(Path(__file__).resolve().parents[3],
        [источник, *ИСТОЧНИКИ_КАТАЛОГОВ])
    каталоги = [нормализовать(значение) for значение in транслитерации]
    требовать(совпадение['title'] == каталоги[0], 'имя не выведено штатно из sourceLabel')
    требовать(len(set(каталоги[1:])) == len(каталоги[1:]), 'коллизия собственных подкаталогов')
    требовать(dict(zip(ИСТОЧНИКИ_КАТАЛОГОВ, каталоги[1:])) == каталоги_формата(),
        'штатное преобразование не совпало с закреплённой политикой')
    return {'схема': СХЕМА, 'алгоритм': АЛГОРИТМ, 'ревизия': РЕВИЗИЯ,
        'sourceLabel': источник, 'title': заголовок, 'транслитерации': транслитерации,
        'каталоги': dict(zip(ИСТОЧНИКИ_КАТАЛОГОВ, каталоги[1:]))}


def проверить_данные(корень, имя, данные):
    требовать(type(данные) is dict and set(данные) == {'схема', 'алгоритм', 'ревизия',
        'sourceLabel', 'title', 'транслитерации', 'каталоги'}, 'неверные поля имени Журнала.2')
    требовать(данные['схема'] == СХЕМА and данные['алгоритм'] == АЛГОРИТМ
        and данные['ревизия'] == РЕВИЗИЯ, 'неизвестная версия алгоритма имени')
    требовать(данные == построить_имя(корень, имя, данные['sourceLabel'], данные['title']),
        'подменена связь русского источника и каталогов')
    return данные


def свойства(текст, имя, *, корень=None):
    строки = текст.splitlines()
    требовать(len(строки) >= 4 and строки[0].startswith('# ') and строки[1] == ''
        and строки[2] == МАРКЕР and строки[3].startswith('<!-- FUM-ОБЫЧНЫЙ-ЭТАП: ')
        and строки[3].endswith(' -->'), 'нет единственных видимых метаданных пары.2')
    контракт = _контракт_имени()
    видимое = _видимые_строки(текст)
    требовать(видимое.count('FUM-ОБЫЧНЫЙ-ЖУРНАЛ:') == 1
        and видимое.count('FUM-ОБЫЧНЫЙ-ЭТАП:') == 1, 'повторные метаданные пары.2')
    сырые = строки[3][len('<!-- FUM-ОБЫЧНЫЙ-ЭТАП: '):-len(' -->')]
    данные = _разобрать_метаданные(сырые)
    контракт.поля(данные, {'журнал', 'задача', 'писатель', 'основание', 'этап', 'имя'})
    требовать(сырые.encode() == контракт.канон(данные) and данные['журнал'] == имя,
        'неканонические или чужие метаданные пары.2')
    контракт.идентичность(данные['задача']); контракт.идентичность(данные['писатель'])
    контракт.селектор(данные['основание']); контракт.отпечаток(данные['этап'])
    проверить_данные(корень or Path(__file__).resolve().parents[3], имя, данные['имя'])
    совпадение = разобрать_имя(имя)
    время = совпадение['date'] + ' ' + ':'.join(совпадение[к] for к in ('hour', 'minute', 'second')) + ' MSK'
    ожидаемый = время + ' - ' + данные['имя']['title']
    требовать(строки[0] in {'# Исходный запрос ' + ожидаемый, '# Отчёт ' + ожидаемый},
        'русский H1 не связан с sourceLabel')
    return данные


def отрендерить_пару(корень, журнал, метка, заголовок, задача, команды, *, писатель, основание):
    import независимый_журнал as прежний
    данные_имени = построить_имя(корень, журнал, метка, заголовок)
    совпадение = разобрать_имя(журнал)
    прежнее_имя = совпадение['prefix'][:-3] + 'MSK_' + метка
    файлы, план = прежний.отрендерить_пару(корень, прежнее_имя, метка, заголовок, задача,
        команды, писатель=писатель, основание=основание)
    данные = {к: план[к] for к in ('журнал', 'задача', 'писатель', 'основание', 'этап')}
    данные['журнал'] = журнал
    данные['имя'] = данные_имени
    данные['этап'] = прежний.контракт.хэш(прежний.контракт.канон({**{к: з for к, з in данные.items() if к != 'этап'}, 'команды': команды}))
    метаданные = МАРКЕР + '\n<!-- FUM-ОБЫЧНЫЙ-ЭТАП: ' + прежний.контракт.канон(данные).decode() + ' -->'
    новые = []
    каталог = '/'.join(данные_имени['каталоги'][к] for к in ИСТОЧНИКИ_КАТАЛОГОВ)
    for файл in файлы:
        текст = файл.data.decode()
        строки = текст.split('\n', 4)
        требовать(строки[2] == прежний.МАРКЕР, 'изменён результат прежнего renderer')
        текст = '\n'.join(строки[:2]) + '\n' + метаданные + '\n' + строки[4]
        if файл.path.name == 'отчёт.md':
            старый = 'каталог=материалы/запуски-проверок -->'
            требовать(текст.count(старый) == 1, 'неоднозначная граница каталога проверок')
            текст = текст.replace(старый, 'каталог=' + каталог + ' -->', 1)
        новые.append(каркас.PreparedFile(PurePosixPath('Журнал', журнал, файл.path.name), текст.encode(), файл.mode))
    план = {'схема': 'fum.план-обычной-независимой-пары.2', **данные,
        'файлы': [{'путь': ф.path.as_posix(), 'sha256': прежний.контракт.хэш(ф.data), 'режим': ф.mode} for ф in новые],
        'разрешение_установки': False}
    return новые, план


def проверить_план(план, *, корень=None):
    контракт = _контракт_имени()
    контракт.поля(план, {'схема', 'журнал', 'задача', 'писатель', 'основание', 'этап',
        'имя', 'файлы', 'разрешение_установки'})
    требовать(план['схема'] == 'fum.план-обычной-независимой-пары.2'
        and план['разрешение_установки'] is False, 'неверная версия плана пары.2')
    контракт.идентичность(план['задача']); контракт.идентичность(план['писатель'])
    контракт.селектор(план['основание']); контракт.отпечаток(план['этап'])
    проверить_данные(корень or Path(__file__).resolve().parents[3], план['журнал'], план['имя'])
    требовать(type(план['файлы']) is list and len(план['файлы']) == 2, 'нет двух целей плана.2')
    for файл, имя in zip(план['файлы'], ('запрос.md', 'отчёт.md')):
        контракт.поля(файл, {'путь', 'sha256', 'режим'})
        контракт.отпечаток(файл['sha256'])
        требовать(файл['путь'] == str(PurePosixPath('Журнал', план['журнал'], имя))
            and type(файл['режим']) is int and файл['режим'] == 0o644, 'чужая цель плана.2')
    return план


def установить_пару(корень, файлы, план, *, проверить_границу, проверить_установку=None):
    """Файловая операция после отдельного внешнего допуска ROOT, как у P.1."""
    import независимый_журнал as прежний
    проверить_план(план, корень=корень)
    требовать(callable(проверить_границу) and os.environ.get('CODEX_THREAD_ID') == план['писатель'],
        'нет внешней границы или другой писатель пары.2')
    прежний._ресурсы()
    корень = прежний.физический_корень(корень)
    проверить_коллизии(корень, план['журнал'])
    ожидаемые = [ф['путь'] for ф in план['файлы']]

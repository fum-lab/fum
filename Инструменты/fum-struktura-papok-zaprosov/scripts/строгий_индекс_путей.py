"""Одноразовый полный namespace одного строгого прохода.

Индекс не является снимком атомарной ФС. Он требует неизменности наблюдаемых
идентичностей и независимо перечитывает имена перед успешным выходом.
"""
from pathlib import Path
import stat


def идентичность(мета):
    return (мета.st_dev, мета.st_ino, мета.st_mode, мета.st_uid, мета.st_gid,
        мета.st_nlink, мета.st_size, мета.st_mtime_ns, мета.st_ctime_ns)


class ИндексПутей:
    def __init__(сам, корень, ключ, *, внешние_родители=False):
        сам.корень = Path(корень)
        сам.ключ = ключ
        сам.внешние_родители = внешние_родители
        сам.каталоги = {}
        сам.узлы = {}
        сам.ключи = {}
        сам.закрыт = False
        if внешние_родители:
            сам._требовать(сам.корень.is_absolute()
                and сам.корень == сам.корень.resolve()
                and '..' not in сам.корень.parts)
        сам._снять(сам.корень, рекурсивно=False)
        for имя in ('Журнал', 'Индексы'):
            путь = сам.корень / имя
            if путь in сам.узлы and stat.S_ISDIR(сам.узлы[путь][2]):
                сам._снять(путь, рекурсивно=имя == 'Журнал')

    def _требовать(сам, условие):
        if not условие:
            raise ValueError('дрейф namespace строгого прохода')

    def _ключ(сам, имя):
        if имя not in сам.ключи:
            сам.ключи[имя] = сам.ключ(имя)
        return сам.ключи[имя]

    def _снять(сам, родитель, *, рекурсивно, метаданные=True):
        до = идентичность(родитель.lstat())
        сам._требовать(stat.S_ISDIR(до[2]))
        имена = tuple(sorted(п.name for п in родитель.iterdir()))
        группы = {}
        каталоги = []
        for имя in имена:
            группы.setdefault(сам._ключ(имя), []).append(имя)
            путь = родитель / имя
            # Все имена корня участвуют в коллизиях, но метаданные чужих
            # областей (.obsidian и прочих) не становятся входом Журнала.
            if not метаданные or (родитель == сам.корень
                    and имя not in {'Журнал', 'Индексы'}):
                continue
            метка = идентичность(путь.lstat())
            сам.узлы[путь] = метка
            if stat.S_ISDIR(метка[2]):
                каталоги.append(путь)
        сам._требовать(идентичность(родитель.lstat()) == до)
        сам.каталоги[родитель] = (до, имена, группы)
        if рекурсивно:
            for путь in каталоги:
                сам._снять(путь, рекурсивно=True)

    def _наблюдать_узел(сам, путь):
        метка = идентичность(путь.lstat())
        if путь in сам.узлы:
            сам._требовать(метка == сам.узлы[путь])
        else:
            сам.узлы[путь] = метка
        return метка

    def _добавить_родителя(сам, родитель):
        сам._требовать(сам.внешние_родители and родитель.is_absolute()
            and родитель.is_relative_to(сам.корень) and '..' not in родитель.parts)
        текущий = сам.корень
        for часть in родитель.relative_to(сам.корень).parts:
            # Уже снятые предки используют те же группы имён; повторный
            # точный_путь без индекса снова перечислял бы широких соседей.
            сам._требовать(сам.совпадения(текущий, часть) == [часть])
            текущий /= часть
            метка = сам._наблюдать_узел(текущий)
            сам._требовать(stat.S_ISDIR(метка[2]))
            if текущий not in сам.каталоги:
                # Чужие соседние поддеревья не обходятся, а метаданные
                # привязываются только к посещённым компонентам.
                сам._снять(текущий, рекурсивно=False, метаданные=False)

    def совпадения(сам, родитель, часть):
        сам._требовать(not сам.закрыт)
        if родитель not in сам.каталоги:
            сам._добавить_родителя(родитель)
        метка, _, группы = сам.каталоги[родитель]
        сам._требовать(идентичность(родитель.lstat()) == метка)
        совпадения = группы.get(сам._ключ(часть), [])
        if сам.внешние_родители and совпадения == [часть]:
            сам._наблюдать_узел(родитель / часть)
        return совпадения

    def проверить(сам):
        сам._требовать(not сам.закрыт)
        # Это новое независимое перечисление, без повторной нормализации.
        # Сверяются и уже пройденные ветви, и пустые каталоги, и смешанные типы.
        for родитель, (метка, имена, _) in сам.каталоги.items():
            сам._требовать(идентичность(родитель.lstat()) == метка)
            сам._требовать(tuple(sorted(п.name for п in родитель.iterdir())) == имена)
            for имя in имена:
                путь = родитель / имя
                if путь in сам.узлы:
                    сам._требовать(идентичность(путь.lstat()) == сам.узлы[путь])
            сам._требовать(идентичность(родитель.lstat()) == метка)

    def __enter__(сам):
        сам._требовать(not сам.закрыт)
        return сам

    def __exit__(сам, тип, значение, трасса):
        try:
            if тип is None:
                сам.проверить()
        finally:
            сам.закрыт = True
        return False

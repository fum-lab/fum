def байты(данные):
    return публичные.канонические_байты(данные) + b'\n'


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def _приватный(имя, *, отсутствует=False):
    путь = Path(имя)
    if (not путь.is_absolute() or путь != путь.resolve() or any(п.is_symlink() for п in (путь, *путь.parents))
            or any(os.path.lexists(п / '.git') for п in путь.parents)):
        raise ValueError('Приватный адрес должен быть физическим и находиться вне Git')
    if отсутствует:
        if os.path.lexists(путь) or not путь.parent.is_dir():
            raise ValueError('Нужен новый приватный адрес с существующим родителем')
    else:
        состояние = путь.lstat()
        if not stat.S_ISREG(состояние.st_mode) or stat.S_IMODE(состояние.st_mode) not in (0o400, 0o600) or состояние.st_uid != os.getuid():
            raise ValueError('Приватный источник должен принадлежать исполнителю и иметь режим 0400/0600')
    return путь


def _json(имя):
    путь = _приватный(имя)
    if путь.stat().st_size > 16 * 1024 * 1024:
        raise ValueError('Описание превышает конечную границу')
    return наполнение.прочитать_json(путь.read_bytes())


def _допуск(корень, вход):
    if type(вход) is not dict or set(вход) != ПОЛЯ or вход['схема'] != 'fum.переход-публичного-журнала.1':
        raise ValueError('Неверный вход именованного перехода')
    if Path(корень) != Path(корень).resolve():
        raise ValueError('Нужен явный физический корень')
    _приватный(вход['поручение'])
    _приватный(вход['подготовка_коммита'])
    процесс = subprocess.run([sys.executable, '-B', '-I', '-c', КОД_ДОПУСКА,
        str(КОРЕНЬ_КОДА), вход['подготовка_коммита'], вход['поручение']],
        cwd=корень, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
    if процесс.returncode:
        raise ValueError('Штатный допуск открытого .9 отказал: ' + процесс.stderr.decode().splitlines()[-1])
    допуск = наполнение.прочитать_json(процесс.stdout)
    подготовка, параметры = допуск['подготовка'], допуск['параметры']
    if (подготовка['схема'] != 'fum.подготовленный-коммит.9' or параметры['корень'] != str(корень)
            or параметры['задача'] != вход['задача'] or параметры['исполнитель'] != вход['исполнитель']
            or параметры['запрос'] != вход['запрос']):
        raise ValueError('Переход не принадлежит этому открытому обычному дочернему этапу')
    if os.path.lexists(подготовка['готовность']) or os.path.lexists(параметры['квитанция']):
        raise ValueError('Готовый или уже закоммиченный этап не преобразуется')
    публичные._поля(вход['разрешение'], ('путь', 'sha256'))
    разрешение = _приватный(вход['разрешение']['путь'])
    if хэш(разрешение.read_bytes()) != вход['разрешение']['sha256']:
        raise ValueError('Разрешённый состав изменился')
    цели = _json(str(разрешение))
    if type(цели) is not list or цели != параметры['разрешённые_цели']:
        raise ValueError('Состав перехода должен совпадать с обычной подготовкой .9')
    отчёт = str(PurePosixPath(вход['запрос']).with_name('отчёт.md'))
    манифест = вход['манифест']
    наполнение._проверить_имя(манифест)
    if (отчёт not in цели or манифест not in цели
            or not манифест.startswith(str(PurePosixPath(вход['запрос']).parent / 'материалы') + '/')):
        raise ValueError('Манифест и отчёт должны входить в собственный конечный состав')
    if наполнение._загрузить('отчёты').границы_управляемого_блока((Path(корень) / отчёт).read_text())[2] != наполнение._загрузить('отчёты').ОТКРЫТЫЙ_МАРКЕР:
        raise ValueError('Закрытый снимок не преобразуется')
    каталог = Path(корень) / вход['запрос']
    if any(os.path.lexists(каталог.parent / 'материалы/запуски-проверок' / имя) for имя in ('снимок.json', 'возобновление.json')):
        raise ValueError('Снимок или переход закрытия запрещает преобразование')
    return параметры, цели, отчёт, допуск['код']


def _снимок(корень, вход):
    параметры, цели, отчёт, код_допуска = _допуск(корень, вход)
    охват = наполнение._загрузить('охват')
    статус, строки, пути = охват.прочитать_статус(корень)
    if set(пути) - set(цели):
        raise ValueError('Git status вышел за назначенную область')
    кэш = {}
    состояния = {имя: охват.состояние_пути(охват.точный_путь(корень, имя, кэш)) for имя in цели}
    if состояния[отчёт]['тип'] != 'файл' or any(с['тип'] == 'каталог' for с in состояния.values()):
        raise ValueError('Нужны конечные обычные файлы и исходный отчёт')
    прочие = [с for с in строки.splitlines() if set(охват.СВЯЗНОСТЬ.parse_git_status_paths(с)).isdisjoint({отчёт, вход['манифест']})]
    админ = Path(охват.выполнить_git(корень, 'rev-parse', '--absolute-git-dir').decode().strip())
    индекс = админ / 'index'
    служебные = {имя: хэш(_приватный(вход[имя]).read_bytes()) for имя in ('поручение', 'подготовка_коммита')}
    служебные['разрешение'] = хэш(_приватный(вход['разрешение']['путь']).read_bytes())
    return {'корень': str(корень), 'HEAD': параметры['исходный_коммит'], 'ref': параметры['ветка'],
        'владелец': вход['исполнитель'], 'индекс_sha256': хэш(индекс.read_bytes()),
        'индекс_режим': stat.S_IMODE(индекс.stat().st_mode), 'служебные': служебные,
        'прочий_статус_sha256': хэш('\n'.join(прочие).encode()), 'файлы': состояния,
        'код': наполнение._сверить_код(), 'код_допуска': код_допуска}


def _native(событие, закрепление):
    публичные._поля(закрепление, ('путь', 'граница', 'sha256'))
    публичные._хэш(закрепление['sha256'])
    путь = _приватный(закрепление['путь'])
    граница = закрепление['граница']
    источник = событие['источник']
    if type(граница) is not int or not источник['конец'] <= граница <= путь.stat().st_size:
        raise ValueError('Неверный native-префикс или диапазон события')
    сумма = hashlib.sha256()
    with путь.open('rb') as поток:
        первая = поток.readline()
        начало = наполнение.прочитать_json(первая)
        if начало.get('type') != 'session_meta' or начало.get('payload', {}).get('id') != источник['задача']:
            raise ValueError('Native принадлежит другой задаче')
        поток.seek(0)
        осталось = граница
        while осталось:
            часть = поток.read(min(1024 * 1024, осталось))
            if not часть: raise ValueError('Native усечён')
            сумма.update(часть)
            осталось -= len(часть)
        if сумма.hexdigest() != закрепление['sha256']:
            raise ValueError('Native RAW/SHA изменился')
        поток.seek(граница - 1)
        if поток.read(1) != b'\n': raise ValueError('Native-префикс оканчивается внутри записи')
        if источник['начало']:
            поток.seek(источник['начало'] - 1)
            if поток.read(1) != b'\n': raise ValueError('Native начинается внутри записи')
        поток.seek(источник['начало'])
        сырой = поток.read(источник['конец'] - источник['начало'])
    if not сырой.endswith(b'\n') or хэш(сырой) != источник['sha256']:
        raise ValueError('Native диапазон/SHA не соответствует событию')
    запись = наполнение.прочитать_json(сырой)
    нагрузка = запись.get('payload', {})
    if запись.get('type') == 'response_item' and нагрузка.get('type') == 'message':
        роль = {'assistant': 'ассистент', 'user': 'пользователь'}.get(нагрузка.get('role'))
        части = нагрузка.get('content')
        if type(части) is not list or not части or any(type(ч) is not dict or ч.get('type') not in ('input_text', 'output_text') or type(ч.get('text')) is not str for ч in части):
            raise ValueError('Не поддержано текстовое native-событие')
        текст = ''.join(ч['text'] for ч in части)
    elif запись.get('type') == 'event_msg' and нагрузка.get('type') in ('agent_message', 'user_message'):
        роль = 'ассистент' if нагрузка['type'] == 'agent_message' else 'пользователь'
        текст = нагрузка.get('message')
    else:
        raise ValueError('Неподдержанный native-контейнер не преобразуется догадкой')
    if текст != событие['текст'] or роль != событие['роль']:
        raise ValueError('Текст/роль события не соответствуют native RAW')
    return сырой


def _построить(исходные, вход):
    события, (_, конец, _) = блоки._прочитать_с_границами(исходные)
    if type(вход['события']) is not list or not вход['события']:
        raise ValueError('Нужно явно выбрать конечные события')
    выбор, прежний = {}, -1
    оригиналы = []
    связи = []
    for выбранное in вход['события']:
        публичные._поля(выбранное, ('идентификатор', 'оригинал_sha256', 'native', 'замены'))
        позиции = [н for н, с in enumerate(события) if с['идентификатор'] == выбранное['идентификатор']]
        if len(позиции) != 1 or позиции[0] <= прежний:
            raise ValueError('Выбор должен сохранять порядок и каждый экземпляр')
        прежний = позиции[0]
        оригинал = события[прежний]
        if хэш(блоки.канонические_байты(оригинал)) != выбранное['оригинал_sha256']:
            raise ValueError('RAW события не соответствует выбранному SHA')
        оригиналы.append(_native(оригинал, выбранное['native']))
        новое = публичные.сформировать(оригинал, выбранное['замены'])
        if not публичные.проверить_повтор(новое, оригинал):
            raise ValueError('Нет независимой связи представления с оригиналом')
        выбор[прежний] = новое
        связи.append({**публичные.прочитать_связь(новое), 'представление_sha256': хэш(блоки.канонические_байты(новое)),
            'native_префикс_sha256': выбранное['native']['sha256']})
    начало = next(а for а, _, строка in блоки.структурные_строки(исходные) if строка == блоки.НАЧАЛО_ЖУРНАЛА.decode().rstrip('\n'))
    новые = [выбор.get(н, с) for н, с in enumerate(события)]
    результат = исходные[:начало] + блоки.дополнить_журнал(блоки.пустой_курсор(), новые) + исходные[конец:]
    if блоки.прочитать_журнал(результат) != новые:
        raise ValueError('Переход потерял событие, порядок или повтор')
    манифест = {'схема': 'fum.манифест-публичного-журнала.1', 'задача': вход['задача'],
        'исполнитель': вход['исполнитель'], 'исходный_отчёт_sha256': хэш(исходные),
        'публичный_отчёт_sha256': хэш(результат), 'события': связи}
    return результат, байты(манифест), оригиналы


def подготовить(корень, вход, *, профиль=None):
    начало = time.perf_counter_ns()
    корень = Path(корень)
    _приватный(вход['архив'], отсутствует=True)
    до = _снимок(корень, вход)
    отчёт = str(PurePosixPath(вход['запрос']).with_name('отчёт.md'))
    исходные = (корень / отчёт).read_bytes()
    if хэш(исходные) != вход['исходный_отчёт_sha256'] or до['файлы'][вход['манифест']]['тип'] != 'отсутствует':
        raise ValueError('Предпросмотр требует точный исходный отчёт и новый манифест')
    новые, манифест, _ = _построить(исходные, вход)
    после = _снимок(корень, вход)
    if после != до or (корень / отчёт).read_bytes() != исходные:
        raise ValueError('Состояние изменилось при планировании')
    план = {'схема': 'fum.план-публичного-журнала.1', 'вход_sha256': хэш(байты(вход)),
        'зависимости': до, 'файлы': [{'путь': отчёт, 'текст': новые.decode(), 'режим': до['файлы'][отчёт]['режим']},
            {'путь': вход['манифест'], 'текст': манифест.decode(), 'режим': 0o644}]}
    if профиль is not None: профиль['планирование_нс'] = time.perf_counter_ns() - начало
    return план


def _синхронизировать(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try: os.fsync(дескриптор)
    finally: os.close(дескриптор)


def _сохранить(путь, данные):
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o400)
    with os.fdopen(дескриптор, 'wb') as поток:
        поток.write(данные)
        поток.flush()
        os.fsync(поток.fileno())
    _синхронизировать(путь.parent)


def _ожидаемые(план):
    ожидаемые = json.loads(байты(план['зависимости']))
    for файл in план['файлы']:
        ожидаемые['файлы'][файл['путь']] = {'тип': 'файл', 'режим': файл['режим'], 'sha256': хэш(файл['текст'].encode())}
    return ожидаемые


def _архив(вход, план):
    if (type(план) is not dict or set(план) != {'схема', 'вход_sha256', 'зависимости', 'файлы'}
            or план['схема'] != 'fum.план-публичного-журнала.1' or план['вход_sha256'] != хэш(байты(вход))):
        raise ValueError('Неизвестный или изменённый план')
    путь = Path(вход['архив'])
    if (путь != путь.resolve() or путь.is_symlink() or not путь.is_dir()
            or stat.S_IMODE(путь.stat().st_mode) != 0o700 or путь.stat().st_uid != os.getuid()):
        raise ValueError('Нет собственного устойчивого приватного архива')
    обязательные = {'оригинал.bin', 'вход.json', 'план.json', 'намерение.json'} | {
        f'native-{номер}.jsonl' for номер in range(len(вход['события']))}
    имеющиеся = {п.name for п in путь.iterdir()}
    if not обязательные <= имеющиеся or имеющиеся - обязательные - {'результат.json'}:
        raise ValueError('Неизвестный исход сохранения оригинала; эффект запрещён')
    for имя in имеющиеся:
        if stat.S_IMODE(_приватный(str(путь / имя)).stat().st_mode) != 0o400:
            raise ValueError('Неизменный архивный свидетель должен иметь режим 0400')
    if (_приватный(str(путь / 'вход.json')).read_bytes() != байты(вход)
            or _приватный(str(путь / 'план.json')).read_bytes() != байты(план)
            or _приватный(str(путь / 'намерение.json')).read_bytes() != байты({'схема': 'fum.намерение-публичного-журнала.1', 'план_sha256': хэш(байты(план))})):
        raise ValueError('Архив не соответствует точному намерению')
    исходные = _приватный(str(путь / 'оригинал.bin')).read_bytes()
    if хэш(исходные) != вход['исходный_отчёт_sha256']:
        raise ValueError('Неизменный оригинал повреждён')
    новые, манифест, оригиналы = _построить(исходные, вход)
    отчёт = str(PurePosixPath(вход['запрос']).with_name('отчёт.md'))
    ожидаемые_файлы = [{'путь': отчёт, 'текст': новые.decode(), 'режим': план['зависимости']['файлы'][отчёт]['режим']},
        {'путь': вход['манифест'], 'текст': манифест.decode(), 'режим': 0o644}]
    if план['файлы'] != ожидаемые_файлы:
        raise ValueError('План содержит неразрешённый эффект')
    for номер, сырой in enumerate(оригиналы):
        if _приватный(str(путь / f'native-{номер}.jsonl')).read_bytes() != сырой:
            raise ValueError('Сохранённый native-оригинал изменился')
    return путь


def _синхронизировать_архив(вход, план, *, результат=False):
    """Прочитанные байты после lost-fsync ещё не подтверждают устойчивость свидетелей."""
    архив = _архив(вход, план)
    имена = ['оригинал.bin', 'вход.json', 'план.json', 'намерение.json'] + [
        f'native-{номер}.jsonl' for номер in range(len(вход['события']))]
    if результат: имена.append('результат.json')
    for имя in имена:
        with _приватный(str(архив / имя)).open('rb') as поток: os.fsync(поток.fileno())
    _синхронизировать(архив)
    _архив(вход, план)


def проверить(корень, вход, план):
    if план.get('вход_sha256') != хэш(байты(вход)):
        raise ValueError('План относится к другому входу')
    архив = _архив(вход, план)
    if _снимок(Path(корень), вход) != _ожидаемые(план):
        raise ValueError('Установленный результат не подтверждён')
    итог = {'схема': 'fum.переход-публичного-журнала-подтверждён.1', 'план_sha256': хэш(байты(план))}
    if not (архив / 'результат.json').exists() or _приватный(str(архив / 'результат.json')).read_bytes() != байты(итог):
        raise ValueError('Неизвестный исход; требуется явное восстановление')
    return {'схема': 'fum.проверка-публичного-журнала.1', 'подтверждено': True}


def применить(корень, вход, план, *, профиль=None, восстановление=False):
    корень = Path(корень)
    with наполнение._загрузить('отчёты').межпроцессная_блокировка(корень, вход['запрос']):
        if not os.path.lexists(вход['архив']):
            свежий = подготовить(корень, вход)
            if свежий != план:
                raise ValueError('План, индекс или вход изменились; нужен новый предпросмотр')
            начало = time.perf_counter_ns()
            архив = _приватный(вход['архив'], отсутствует=True)
            os.mkdir(архив, 0o700)
            _синхронизировать(архив.parent)
            исходные = (корень / план['файлы'][0]['путь']).read_bytes()
            _, _, оригиналы = _построить(исходные, вход)
            _сохранить(архив / 'оригинал.bin', исходные)
            _сохранить(архив / 'вход.json', байты(вход))
            _сохранить(архив / 'план.json', байты(план))
            for номер, сырой in enumerate(оригиналы): _сохранить(архив / f'native-{номер}.jsonl', сырой)
            _сохранить(архив / 'намерение.json', байты({'схема': 'fum.намерение-публичного-журнала.1', 'план_sha256': хэш(байты(план))}))
            if профиль is not None: профиль['сохранение_оригинала_нс'] = time.perf_counter_ns() - начало
        else:
            архив = _архив(вход, план)
            if (архив / 'результат.json').exists():
                проверить(корень, вход, план)
                _синхронизировать_архив(вход, план, результат=True)
                проверить(корень, вход, план)
                return {'схема': 'fum.применение-публичного-журнала.1', 'повтор': True}
            if not восстановление:
                raise ValueError('Неизвестный исход; эффект не повторяется без явного восстановления')
        текущее = _снимок(корень, вход)
        ожидаемые = _ожидаемые(план)
        if текущее not in (ожидаемые, план['зависимости']):
            raise ValueError('Частичный или изменённый исход; автоматического восстановления нет')
        _синхронизировать_архив(вход, план)
        if _снимок(корень, вход) != текущее:
            raise ValueError('Состояние изменилось во время подтверждения архива')
        начало_установки = time.perf_counter_ns()
        if текущее != ожидаемые:
            if текущее != план['зависимости']:
                raise ValueError('Частичный или изменённый исход; автоматического восстановления нет')
            начало = time.perf_counter_ns()
            подготовленные = [наполнение.каркас.PreparedFile(PurePosixPath(ф['путь']), ф['текст'].encode(), ф['режим']) for ф in план['файлы']]
            def сверить(ожидается):
                _архив(вход, план)
                if _снимок(корень, вход) != ожидается: raise ValueError('Состояние изменилось у границы эффекта')
            наполнение.каркас._apply_prepared_transaction(корень, подготовленные,
                проверить_исходники=lambda: сверить(план['зависимости']), проверить_установку=lambda: сверить(ожидаемые))
        for файл in план['файлы']:
            with (корень / файл['путь']).open('rb') as поток: os.fsync(поток.fileno())
            _синхронизировать((корень / файл['путь']).parent)
        if профиль is not None: профиль['установка_нс'] = time.perf_counter_ns() - начало_установки
        _сохранить(архив / 'результат.json', байты({'схема': 'fum.переход-публичного-журнала-подтверждён.1', 'план_sha256': хэш(байты(план))}))
        проверить(корень, вход, план)
        return {'схема': 'fum.применение-публичного-журнала.1', 'повтор': False}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('режим', choices=('план', 'применить', 'проверить', 'восстановить'))
    разбор.add_argument('--корень', required=True)
    разбор.add_argument('--вход', required=True)
    разбор.add_argument('--план', required=True)
    разбор.add_argument('--sha256')
    аргументы = разбор.parse_args()
    try:
        вход = _json(аргументы.вход)
        if аргументы.режим == 'план':
            if аргументы.sha256 is not None: raise ValueError('План получает SHA из нового результата')
            план = подготовить(Path(аргументы.корень), вход)
            файл = _приватный(аргументы.план, отсутствует=True)
            _сохранить(файл, байты(план))
            результат = {'схема': 'fum.предпросмотр-публичного-журнала.1', 'план_sha256': хэш(байты(план))}
        else:
            файл = _приватный(аргументы.план)
            if хэш(файл.read_bytes()) != аргументы.sha256: raise ValueError('Не совпадает независимо выбранный SHA плана')
            план = _json(str(файл))
            результат = (проверить(Path(аргументы.корень), вход, план) if аргументы.режим == 'проверить' else
                применить(Path(аргументы.корень), вход, план, восстановление=аргументы.режим == 'восстановить'))
        print(байты(результат).decode(), end='')
        return 0
    except (ValueError, OSError, KeyError, TypeError) as ошибка:
        print(байты({'схема': 'fum.отказ-публичного-журнала.1', 'причина': str(ошибка), 'повтор_автоматически': False}).decode(), file=sys.stderr, end='')
        return 2



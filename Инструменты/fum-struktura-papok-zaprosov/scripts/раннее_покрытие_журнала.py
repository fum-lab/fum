"""Дешёвая сверка путей закрытых пар перед установкой и подготовкой коммита.

Успех не заменяет проверку байтов, материалов, навигации и полномочий.
"""
from pathlib import PurePosixPath
import независимый_журнал as журнал
from связность_независимого_журнала import прочитать_объект_гита
import контракт_независимого_журнала as контракт


def проверить(корень, выбранный, коммит):
    корень = журнал.физический_корень(корень)
    контракт.селектор({'коммит': коммит, 'путь': 'Журнал/README.md', 'sha256': '0' * 64})
    def текущая_вершина():
        return журнал._гит(корень, 'rev-parse', 'HEAD').decode().strip()
    контракт.требовать(текущая_вершина() == коммит, 'изменился выбранный HEAD')
    сырые = прочитать_объект_гита(корень, выбранный)
    состав = журнал._разобрать_данные(сырые)
    контракт.требовать(type(состав) is dict
        and состав.get('схема') == журнал.СХЕМА_СОСТАВА
        and type(состав.get('записи')) is list, 'нужен отдельный S.1')
    принято = []
    for запись in состав['записи']:
        контракт.требовать(type(запись) is dict and type(запись.get('файлы')) is list,
            'неверная запись состава')
        for файл in запись['файлы']:
            контракт.требовать(type(файл) is dict and type(файл.get('путь')) is str,
                'неверный путь состава')
            путь = файл['путь']; контракт.путь(путь)
            части = PurePosixPath(путь).parts
            контракт.требовать(len(части) == 3 and части[0] == 'Журнал'
                and части[2] in {'запрос.md', 'отчёт.md'}, 'посторонний путь состава')
            принято.append(путь)
    контракт.требовать(len(принято) == len(set(принято)), 'повтор пути состава')
    фактически = set()
    for запись in журнал._гит(корень, 'ls-tree', '-r', '-z', '--full-tree', коммит, '--', 'Журнал').split(b'\0'):
        if not запись: continue
        мета, имя = запись.split(b'\t', 1)
        путь = имя.decode(); части = PurePosixPath(путь).parts
        if len(части) == 3 and части[2] in {'запрос.md', 'отчёт.md'}:
            режим, тип, _ = мета.decode().split()
            контракт.требовать((режим, тип) == ('100644', 'blob'), 'необычный Git-файл пары')
            фактически.add(путь)
    контракт.требовать(текущая_вершина() == коммит, 'HEAD изменился при сверке покрытия')
    пропущены, лишние = sorted(фактически - set(принято)), sorted(set(принято) - фактически)
    контракт.требовать(not пропущены and not лишние,
        'состав не покрывает закрытые пары HEAD: ' + str({'пропущены': пропущены, 'лишние': лишние}))
    return {'покрытие': True, 'коммит': коммит, 'состав_sha256': контракт.хэш(сырые),
        'файлов_пар': len(фактически), 'полная_проверка': False}


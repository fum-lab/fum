"""Рендер хранимых шаблонов; защищённые исходники и чужие блоки не переписываются."""
from __future__ import annotations

import posixpath
import hashlib
from pathlib import Path
import re
from urllib.parse import quote

import request_folder_layout as каркас
import управляемые_блоки as блоки

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


ШАБЛОНЫ = {
    'блок-инструментов.md.шаблон': frozenset({'время', 'инструменты'}),
    'блок-профиля.md.шаблон': frozenset({'стадии', 'граница'}),
    'блок-состава.md.шаблон': frozenset({'ссылки'}),
    'блок-текста.md.шаблон': frozenset({'содержание'}),
    'блок-проверок.md.шаблон': frozenset({'содержание', 'запуски'}),
}
РАЗДЕЛЫ_ЗАПРОСА = ('Навигация по запросам', 'Текст запроса', 'Идентификатор сеанса Codex',
                   'Использованные инструменты', 'Проверки', 'Повлиял на файлы')
РАЗДЕЛЫ_ОТЧЁТА = ('Профиль времени выполнения', 'Проверки', 'Решения и ограничения', 'Источники')


def _текст(значение, *, однострочный=False):
    if type(значение) is not str or not значение.strip() or '\x00' in значение:
        raise ValueError('Требуется непустое явно заданное содержание')
    if однострочный and any(знак in значение for знак in '\r\n'):
        raise ValueError('Значение должно помещаться в одной строке')
    return значение


def _поля(значение, имена):
    if type(значение) is not dict or set(значение) != set(имена):
        raise ValueError('Неверный набор полей наполнения')


def _ячейка(значение):
    return _текст(значение, однострочный=True).replace('\\', '\\\\').replace('|', '\\|')


def _секунды(значение):
    if type(значение) is not int or значение < 0:
        raise ValueError('Длительность должна быть целым неотрицательным числом наносекунд')
    целые, дробные = divmod(значение, 1_000_000_000)
    return str(целые) + (',' + f'{дробные:09d}'.rstrip('0') if дробные else '') + ' с'


def прочитать_шаблоны():
    результат = {}
    for имя, поля in ШАБЛОНЫ.items():
        текст = каркас._прочитать_шаблон(имя, поля)
        состояние = {}
        for _, _, строка in блоки.структурные_строки(текст.encode(), состояние=состояние):
            if строка.startswith(('#', '<!-- FUM-')):
                raise ValueError('Шаблон тела не вправе объявлять заголовки или управляемые границы')
        if состояние['ограда'] is not None or состояние['комментарий']:
            raise ValueError('Шаблон тела оставляет незакрытую область Markdown')
        результат[имя] = текст
    return результат


def _секции(байты, ожидаемые):
    строки = list(блоки.структурные_строки(байты))
    заголовки = [(а, б, строка[3:]) for а, б, строка in строки if строка.startswith('## ')]
    if tuple(имя for _, _, имя in заголовки) != ожидаемые:
        raise ValueError('Неверный порядок или повторение структурных разделов карточки')
    результат = {}
    for номер, (_, конец, имя) in enumerate(заголовки):
        граница = заголовки[номер + 1][0] if номер + 1 < len(заголовки) else len(байты)
        результат[имя] = (конец, граница)
    return результат, строки, заголовки[0][0]


def _проверки_в_отчёте(байты, отчёты):
    текст = байты.decode()
    а, б, маркер = отчёты.границы_управляемого_блока(текст)
    if маркер != отчёты.ОТКРЫТЫЙ_МАРКЕР:
        raise ValueError('Закрытую карточку нельзя заново открывать наполнителем')
    начало, конец = len(текст[:а].encode()), len(текст[:б].encode())
    return начало, конец


def _положение(байты, отчёт=False):
    разделы, строки, первое = _секции(байты, РАЗДЕЛЫ_ОТЧЁТА if отчёт else РАЗДЕЛЫ_ЗАПРОСА)
    if отчёт:
        заголовок = [(а, б) for а, б, строка in строки if строка.startswith('# ')]
        прямые = [(а, б) for а, б, строка in строки if строка == '### Прямые запуски проверок']
        профиль = разделы['Профиль времени выполнения']
        if (len(заголовок) != 1 or len(прямые) != 1
                or not профиль[0] < прямые[0][0] < профиль[1]):
            raise ValueError('Неверная граница вводного итога или профиля отчёта')
        return {'итог': (заголовок[0][1], первое), 'профиль': (профиль[0], прямые[0][0]),
                'проверки-отчёта': разделы['Проверки'], 'решения': разделы['Решения и ограничения']}
    return {'инструменты': разделы['Использованные инструменты'],
            'проверки-запроса': разделы['Проверки'], 'состав': разделы['Повлиял на файлы']}


def _поставить_границы(байты, положения):
    границы = блоки.границы_блоков(байты)
    if границы:
        if set(границы) != set(положения):
            raise ValueError('Частичная или посторонняя разметка управляемых блоков')
        for имя, (начало, конец, _) in границы.items():
            а, б = положения[имя]
            if not а <= начало <= конец <= б:
                raise ValueError('Управляемый блок вышел из назначенного раздела')
        return байты
    результат = байты
    for имя, (а, б) in sorted(положения.items(), key=lambda пара: пара[1][0], reverse=True):
        перевод = b'\r\n' if байты[:а].endswith(b'\r\n') else b'\n'
        начало = f'<!-- FUM-КАРТОЧКА:НАЧАЛО {имя} -->'.encode() + перевод
        конец = f'<!-- FUM-КАРТОЧКА:КОНЕЦ {имя} -->'.encode() + перевод
        результат = результат[:а] + перевод + начало + байты[а:б] + конец + перевод + результат[б:]
    return результат


def _защищённое(байты, положения):
    результат = []
    позиция = 0
    for а, б in sorted(положения.values()):
        результат.append(байты[позиция:а])
        позиция = б
    результат.append(байты[позиция:])
    return результат


def _ссылка(путь, папка, ожидаемый=False):
    метка = re.sub(r'([\\\[\]*_`<>])', r'\\\1', путь)
    цель = quote(posixpath.relpath(путь, папка), safe='/.-_~')
    return f'- [{метка}]({цель})' + (' — ожидаемый файл; точная цель предстоящей проверки.' if ожидаемый else '')


def _проверить_владение(запрос, задача):
    разделы, строки, _ = _секции(запрос, РАЗДЕЛЫ_ЗАПРОСА)
    а, б = разделы['Идентификатор сеанса Codex']
    идентификаторы = [(начало, конец, строка) for начало, конец, строка in строки
                      if строка.startswith('Codex-Thread-ID:')]
    if (len(идентификаторы) != 1 or идентификаторы[0][2] != 'Codex-Thread-ID: ' + задача
            or not а <= идентификаторы[0][0] < идентификаторы[0][1] <= б):
        raise ValueError('Собственный UUID должен быть единственным и находиться в разделе идентификатора')


def _журнал_до_рендера(байты, положения):
    маркеры = [(а, б, строка) for а, б, строка in блоки.структурные_строки(байты)
               if строка.startswith('<!-- FUM-ЖУРНАЛ:')]
    if not маркеры:
        return None
    _, (курсор, конец, _) = блоки._прочитать_с_границами(байты)
    начало = маркеры[0][0]
    заменяемые = блоки.границы_блоков(байты)
    тела = [(а, б) for а, б, _ in заменяемые.values()] if заменяемые else list(положения.values())
    if any(а < конец and начало < б for а, б in тела):
        raise ValueError('Журнал пересекает заменяемое тело; прежние записи нельзя удалять рендером')
    решения = положения['решения']
    if not решения[0] <= начало < конец <= решения[1]:
        raise ValueError('Журнал должен находиться в разделе решений вне генерируемого тела')
    return байты[начало:курсор]


def _цель_состава(путь, папка, ожидаемые, состояния):
    if состояния[путь]['тип'] == 'отсутствует' and путь not in ожидаемые:
        if '`' in путь:
            raise ValueError('Удалённая цель не представима точным маркером состава')
        return '- Удалённый файл: `' + путь + '`'
    return _ссылка(путь, папка, путь in ожидаемые)


def сформировать(запрос, отчёт, вход, разрешённые, записи, отчёты, состояния):
    шаблоны = прочитать_шаблоны()
    положения_запроса = _положение(запрос)
    положения_отчёта = _положение(отчёт, True)
    блок_проверок = _проверки_в_отчёте(отчёт, отчёты)
    if not положения_отчёта['профиль'][1] < блок_проверок[0] < блок_проверок[1] < положения_отчёта['проверки-отчёта'][0]:
        raise ValueError('Чужой блок прямых проверок находится за пределами своего раздела')
    _проверить_владение(запрос, вход['задача'])
    прежний_журнал = _журнал_до_рендера(отчёт, положения_отчёта)
    имя_папки = вход['запрос'].split('/')[1]
    время = каркас._expected_header_label(имя_папки)
    заголовок_запроса = '# Исходный запрос ' + время + ' - '
    заголовок_отчёта = '# Отчёт ' + время + ' - '
    первая_запроса = запрос.decode().splitlines()[0]
    if not первая_запроса.startswith(заголовок_запроса) or отчёт.decode().splitlines()[0] != заголовок_отчёта + первая_запроса[len(заголовок_запроса):]:
        raise ValueError('Заголовки пары не совпадают с канонической папкой и временем')
    if type(вход['инструменты']) is not list or not вход['инструменты']:
        raise ValueError('Требуется явный список использованных инструментов')
    инструменты = []
    for инструмент in вход['инструменты']:
        _поля(инструмент, ('имя', 'слой', 'версия', 'основание'))
        версия = 'версия не наблюдалась' if инструмент['версия'] is None else _текст(инструмент['версия'], однострочный=True)
        инструменты.append('- ' + _текст(инструмент['имя'], однострочный=True) + ' (' + _текст(инструмент['слой'], однострочный=True)
                           + '); ' + версия + '; основание: ' + _текст(инструмент['основание'], однострочный=True) + '.')
    _поля(вход['профиль'], ('граница', 'стадии'))
    стадии = вход['профиль']['стадии']
    if type(стадии) is not list or len(стадии) < 2:
        raise ValueError('Профиль требует хотя бы две явно описанные стадии')
    строки_профиля = []
    for стадия in стадии:
        _поля(стадия, ('имя', 'длительность_нс', 'основание'))
        длительность = 'не измерено' if стадия['длительность_нс'] is None else _секунды(стадия['длительность_нс'])
        строки_профиля.append('| ' + ' | '.join((_ячейка(стадия['имя']), длительность, _ячейка(стадия['основание']))) + ' |')
    _поля(вход['поля'], ('итог', 'проверки', 'решения_и_ограничения'))
    запуски = []
    for путь, запись, _ in записи:
        ссылка = _ссылка(путь, '/'.join(вход['запрос'].split('/')[:-1]))
        запуски.append(ссылка + ' — ' + _текст(запись['вызов'], однострочный=True)
                       + '; ' + запись['статус'] + '; код ' + str(запись['код_завершения'])
                       + '; ' + _секунды(запись['длительность_наносекунды']) + '.')
    общие_проверки = каркас._заполнить_шаблон(шаблоны['блок-проверок.md.шаблон'],
        {'содержание': _текст(вход['поля']['проверки']), 'запуски': '\n'.join(запуски) or 'Прямые запуски ещё не зарегистрированы.'}).encode()
    данные_запроса = {
        'инструменты': каркас._заполнить_шаблон(шаблоны['блок-инструментов.md.шаблон'], {'время': время, 'инструменты': '\n'.join(инструменты)}).encode(),
        'проверки-запроса': общие_проверки,
        'состав': каркас._заполнить_шаблон(шаблоны['блок-состава.md.шаблон'],
            {'ссылки': '\n'.join(_цель_состава(путь, '/'.join(вход['запрос'].split('/')[:-1]), вход['ожидаемые_цели'], состояния) for путь in sorted(разрешённые))}).encode(),
    }
    данные_отчёта = {
        'итог': каркас._заполнить_шаблон(шаблоны['блок-текста.md.шаблон'], {'содержание': _текст(вход['поля']['итог'])}).encode(),
        'профиль': каркас._заполнить_шаблон(шаблоны['блок-профиля.md.шаблон'],
            {'стадии': '\n'.join(строки_профиля), 'граница': _текст(вход['профиль']['граница'], однострочный=True)}).encode(),
        'проверки-отчёта': общие_проверки,
        'решения': каркас._заполнить_шаблон(шаблоны['блок-текста.md.шаблон'], {'содержание': _текст(вход['поля']['решения_и_ограничения'])}).encode(),
    }
    новый_запрос = блоки.заменить_блоки(_поставить_границы(запрос, положения_запроса), данные_запроса)
    новый_отчёт = блоки.заменить_блоки(_поставить_границы(отчёт, положения_отчёта), данные_отчёта)
    журнальные = [строка for _, _, строка in блоки.структурные_строки(новый_отчёт) if строка.startswith('<!-- FUM-ЖУРНАЛ:')]
    if not журнальные:
        секции, _, _ = _секции(новый_отчёт, РАЗДЕЛЫ_ОТЧЁТА)
        место = секции['Решения и ограничения'][1]
        новый_отчёт = новый_отчёт[:место] + блоки.пустой_курсор() + b'\n' + новый_отчёт[место:]
    новый_отчёт = блоки.дополнить_журнал(новый_отчёт, вход['вставки'])
    if прежний_журнал is not None:
        _, (курсор, _, _) = блоки._прочитать_с_границами(новый_отчёт)
        начало = next(а for а, _, строка in блоки.структурные_строки(новый_отчёт)
                      if строка == блоки.НАЧАЛО_ЖУРНАЛА.decode().rstrip('\n'))
        if новый_отчёт[начало:начало + len(прежний_журнал)] != прежний_журнал or начало + len(прежний_журнал) > курсор:
            raise ValueError('Рендер изменил прежний префикс журнала')
    if (_защищённое(запрос, положения_запроса) != _защищённое(новый_запрос, _положение(новый_запрос))
            or _защищённое(отчёт, положения_отчёта) != _защищённое(новый_отчёт, _положение(новый_отчёт, True))):
        raise ValueError('Рендер изменил защищённые байты карточки')
    _проверки_в_отчёте(новый_отчёт, отчёты)
    _проверить_владение(новый_запрос, вход['задача'])
    return новый_запрос, новый_отчёт

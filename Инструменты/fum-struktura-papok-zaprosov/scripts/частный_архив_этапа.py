def _результат(вход, план, выбор, состояние):
    корень = точный(вход['корень'])
    источник = корень / вход['источник']
    архив, _, _ = _пути_состояния(вход)
    родитель = метаданные(архив.parent)
    требовать(all(родитель[к] == план['родитель_архива'][к] for к in родитель if к != 'nlink'),
        'подменён родитель сохранённого архива')
    требовать(снимок_гита(корень) == план['снимок'], 'дрейф HEAD/ref/index')
    сохранён = архив.is_dir() and снять_состав(архив) == план['состав']
    требовать(сохранён and not os.path.lexists(источник), 'неизвестно расположение единственной подтверждённой копии')
    if состояние != 'готово':
        return {'схема': СХЕМА, 'состояние': 'неизвестно', 'архив_подтверждён': True,
            'план_sha256': выбор['план_sha256'], 'повторного_переноса': False, 'коммит_создан': False}
    for э in план['публичные_файлы']:
        сведения, _ = файл(точный(str(корень / э['путь'])))
        требовать(сведения['sha256'] == э['sha256'] and сведения['режим'] == э['режим'], 'дрейф публичного J2')
    новый = корень / 'Журнал' / вход['новый']['основа']
    ожидаемые = {Path(э['путь']).relative_to(новый.relative_to(корень)).as_posix()
        for э in план['публичные_файлы'] if (корень / э['путь']).is_relative_to(новый)}
    фактические = {э['путь'] for э in снять_состав(новый) if э['тип'] == 'файл'}
    требовать(фактические == ожидаемые and all(э['тип'] == 'файл' or э['путь'] == '.'
        for э in снять_состав(новый)), 'лишний объект публичного J2')
    return {'схема': СХЕМА, 'состояние': 'готово', 'архив_подтверждён': True,
        'план_sha256': выбор['план_sha256'], 'повторного_переноса': False, 'коммит_создан': False}


def проверить(вход, план, выбор):
    _выбор(план, выбор)
    требовать(хэш(байты(вход)) == план['вход_sha256'], 'подменён вход')
    _, путь, _ = _пути_состояния(вход)
    данные = _частные_байты(путь)
    состояние = _разобрать_байты(данные)
    поля(состояние, {'схема', 'план_sha256', 'выбор_sha256', 'состояние'})
    требовать(данные == байты(состояние) and состояние['схема'] == СХЕМА
        and состояние['план_sha256'] == хэш(байты(план)) and состояние['выбор_sha256'] == хэш(байты(выбор))
        and состояние['состояние'] in {'намерение', 'архивирован', 'неизвестно', 'готово'}, 'подменена квитанция')
    _, обычное, _, сведения_кода = код(вход['код'])
    требовать(сведения_кода == план['код'], 'изменён код сохранённого перехода')
    обычное.проверить(вход['поручение'], выбор['поручение'])
    результат = _результат(вход, план, выбор, состояние['состояние'])
    if результат['состояние'] == 'готово':
        архив, _, _ = _пути_состояния(вход)
        for э in reversed(план['состав']):
            _синхронизировать(архив / э['путь'])
        for э in план['публичные_файлы']:
            _синхронизировать(Path(вход['корень']) / э['путь'])
            _синхронизировать((Path(вход['корень']) / э['путь']).parent)
        for п in [архив.parent, (Path(вход['корень']) / вход['источник']).parent, путь, путь.parent]:
            _синхронизировать(п)
        требовать(_результат(вход, план, выбор, состояние['состояние']) == результат, 'дрейф повтора')
    return результат


def применить(вход, план, выбор, *, профиль=None):
    начало = time.perf_counter_ns()
    _выбор(план, выбор)
    архив, квитанция, замок = _пути_состояния(вход)
    дескриптор = os.open(замок, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    try:
        требовать(метаданные(замок)['режим'] == 0o600, 'чужой замок')
        fcntl.flock(дескриптор, fcntl.LOCK_EX)
        требовать((os.fstat(дескриптор).st_dev, os.fstat(дескриптор).st_ino)
            == (замок.lstat().st_dev, замок.lstat().st_ino), 'подмена открытого замка')
        if квитанция.exists():
            return проверить(вход, план, выбор)
        свежий = планировать(вход, выбор['поручение'])
        требовать(свежий == план, 'дрейф плана перед эффектом: ' + ','.join(к for к in свежий if свежий[к] != план.get(к)))
        этап, _, _, _ = код(вход['код'])
        корень = Path(вход['корень'])
        источник = корень / вход['источник']
        отчёты = этап.коммит.отчёты
        сессия = (PurePosixPath(вход['источник']) / 'запрос.md').as_posix()
        with отчёты.межпроцессная_блокировка(корень, сессия):
            терминальный(корень, источник, отчёты)
            требовать(снять_состав(источник) == план['состав'] and снимок_гита(корень) == план['снимок']
                and метаданные(архив.parent) == план['родитель_архива'], 'дрейф непосредственно перед намерением')
            if профиль is not None:
                профиль['подготовка_наносекунды'] = time.perf_counter_ns() - начало
            состояние = {'схема': СХЕМА, 'план_sha256': хэш(байты(план)),
                'выбор_sha256': хэш(байты(выбор)), 'состояние': 'намерение'}
            _записать(квитанция, байты(состояние), новый=True)
            родитель_после_намерения = метаданные(архив.parent)
            начало_эффекта = time.perf_counter_ns()
            try:
                for э in reversed(план['состав']):
                    _синхронизировать(источник / э['путь'])
                требовать(снять_состав(источник) == план['состав'] and снимок_гита(корень) == план['снимок']
                    and метаданные(архив.parent) == родитель_после_намерения
                    and not os.path.lexists(архив)
                    and _журнальные_входы(корень, источник, этап.каркас) == план['журнальные_входы']
                    and _каталоги_назначений(корень, план['публичные_файлы']) == план['каталоги_назначений']
                    and _команды(этап, вход) == план['команды'], 'дрейф после синхронизации до переноса')
                код(вход['код'])
                _перенести_исключительно(источник, архив)
                _синхронизировать(источник.parent)
                _синхронизировать(архив.parent)
                требовать(снять_состав(архив) == план['состав'], 'дрейф перенесённого архива')
                состояние['состояние'] = 'архивирован'
                _записать(квитанция, байты(состояние))
                if профиль is not None:
                    профиль['архив_наносекунды'] = time.perf_counter_ns() - начало_эффекта
                начало_публичного = time.perf_counter_ns()
                требовать(снимок_гита(корень) == план['снимок']
                    and _журнальные_входы(корень, источник, этап.каркас) == план['журнальные_входы'], 'дрейф до J2')
                for э in план['публичные_файлы']:
                    цель = корень / э['путь']
                    требовать((файл(цель)[0] if цель.exists() else None) == э['до'], 'дрейф публичного назначения')
                    _публично_записать(корень, э)
                if профиль is not None:
                    профиль['публичная_пара_наносекунды'] = time.perf_counter_ns() - начало_публичного
                начало_сверки = time.perf_counter_ns()
                результат = _результат(вход, план, выбор, 'готово')
                состояние['состояние'] = 'готово'
                _записать(квитанция, байты(состояние))
                if профиль is not None:
                    профиль['сверка_наносекунды'] = time.perf_counter_ns() - начало_сверки
                return результат
            except BaseException:
                состояние['состояние'] = 'неизвестно'
                with contextlib.suppress(OSError):
                    _записать(квитанция, байты(состояние))
                raise
    finally:
        fcntl.flock(дескриптор, fcntl.LOCK_UN)
        os.close(дескриптор)


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('действие', choices=['план', 'применить', 'проверить'])
    разбор.add_argument('--вход', required=True)
    разбор.add_argument('--поручение')
    разбор.add_argument('--план')
    разбор.add_argument('--выбор')
    параметры = разбор.parse_args()
    try:
        вход = прочитать(параметры.вход)
        if параметры.действие == 'план':
            результат = планировать(вход, прочитать(параметры.поручение))
        else:
            функция = применить if параметры.действие == 'применить' else проверить
            результат = функция(вход, прочитать(параметры.план), прочитать(параметры.выбор))
        print(байты(результат).decode(), end='')
        return 0 if результат.get('состояние') != 'неизвестно' else 3
    except Exception as ошибка:
        # Полные входы и вывод CLI остаются приватными; машинная ошибка не содержит путей.
        print(байты({'схема': СХЕМА, 'состояние': 'отказ', 'причина': type(ошибка).__name__}).decode(), end='')
        return 2


if __name__ == '__main__':
    sys.exit(главная())

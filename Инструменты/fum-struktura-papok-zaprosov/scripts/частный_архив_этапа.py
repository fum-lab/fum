def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def хэш(значение):
    return hashlib.sha256(значение).hexdigest()


def поля(значение, имена):
    требовать(type(значение) is dict and set(значение) == set(имена), 'неверные закрытые поля')


def _пары(пары):
    результат = {}
    for имя, значение in пары:
        требовать(имя not in результат, 'повторное поле JSON')
        результат[имя] = значение
    return результат


def _разобрать_байты(данные):
    return json.loads(данные, object_pairs_hook=_пары,
        parse_constant=lambda значение: требовать(False, 'нечисловая константа JSON'))


def _частные_байты(значение):
    путь = точный(str(значение))
    вне_гита(путь)
    родитель = метаданные(путь.parent)
    требовать(родитель['тип'] == 'каталог' and родитель['режим'] == 0o700, 'нечастный родитель JSON')
    сведения, данные = файл(путь)
    требовать(сведения['режим'] == 0o600 and метаданные(путь.parent) == родитель, 'нечастный или изменённый JSON')
    return данные


def прочитать(путь):
    return _разобрать_байты(_частные_байты(путь))


def гит(корень, *аргументы):
    запрещены = {'GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR',
        'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES', 'GIT_CONFIG_COUNT',
        'GIT_CONFIG_PARAMETERS', 'GIT_REPLACE_REF_BASE', 'GIT_NAMESPACE', 'GIT_SHALLOW_FILE'}
    требовать(not запрещены.intersection(os.environ), 'перенаправление Git запрещено')
    среда = dict(os.environ, GIT_OPTIONAL_LOCKS='0', GIT_NO_REPLACE_OBJECTS='1')
    итог = subprocess.run(['git', '-C', str(корень), *аргументы], env=среда,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    требовать(итог.returncode == 0, 'чтение Git отказало')
    return итог.stdout


def точный(значение, существует=True):
    путь = Path(значение)
    требовать(путь.is_absolute() and '..' not in путь.parts and str(путь) == значение,
        'нужен точный абсолютный путь')
    for часть in reversed([путь, *путь.parents]):
        требовать(not часть.is_symlink(), 'символическая ссылка запрещена')
    требовать(путь == путь.resolve(), 'нужен физический путь')
    требовать(not существует or путь.exists(), 'путь отсутствует')
    return путь


def вне_гита(путь):
    for часть in [путь, *путь.parents]:
        требовать(not (часть / '.git').exists() and not (часть / '.git').is_symlink()
            and not (os.path.lexists(часть / 'HEAD') and
                (os.path.lexists(часть / 'objects') or os.path.lexists(часть / 'commondir'))),
            'архив должен находиться вне любого Git')


def метаданные(путь):
    с = путь.lstat()
    требовать(stat.S_ISREG(с.st_mode) or stat.S_ISDIR(с.st_mode), 'неподдержанный тип')
    требовать(с.st_uid == os.getuid() and not (с.st_mode & 0o7022), 'чужой владелец или режим')
    if stat.S_ISREG(с.st_mode):
        требовать(с.st_nlink == 1, 'жёсткая ссылка запрещена')
    return {'тип': 'каталог' if stat.S_ISDIR(с.st_mode) else 'файл',
        'режим': stat.S_IMODE(с.st_mode), 'uid': с.st_uid, 'gid': с.st_gid,
        'nlink': с.st_nlink, 'dev': с.st_dev, 'inode': с.st_ino}


def файл(путь):
    до = метаданные(путь)
    требовать(до['тип'] == 'файл', 'ожидается обычный файл')
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        с = os.fstat(поток.fileno())
        требовать((с.st_dev, с.st_ino, stat.S_IMODE(с.st_mode), с.st_uid, с.st_gid, с.st_nlink)
            == (до['dev'], до['inode'], до['режим'], до['uid'], до['gid'], до['nlink']), 'подмена открываемого файла')
        данные = поток.read()
        после = os.fstat(поток.fileno())
    требовать((с.st_dev, с.st_ino, с.st_size, с.st_mtime_ns, с.st_ctime_ns)
        == (после.st_dev, после.st_ino, после.st_size, после.st_mtime_ns, после.st_ctime_ns)
        and метаданные(путь) == до and len(данные) == с.st_size, 'дрейф файла')
    return {**до, 'байтов': len(данные), 'sha256': хэш(данные)}, данные


def снять_состав(корень):
    результат = []

    def посетить(путь):
        относительный = путь.relative_to(корень).as_posix()
        с = метаданные(путь)
        требовать(путь.name != '.git', 'вложенный Git запрещён')
        if с['тип'] == 'каталог':
            требовать(not (os.path.lexists(путь / 'HEAD') and
                (os.path.lexists(путь / 'objects') or os.path.lexists(путь / 'commondir'))), 'вложенный bare Git')
            имена = sorted(э.name for э in путь.iterdir())
            результат.append({'путь': относительный, **с})
            for имя in имена:
                посетить(путь / имя)
            требовать(имена == sorted(э.name for э in путь.iterdir()) and метаданные(путь) == с,
                'дрейф каталога')
        else:
            сведения, _ = файл(путь)
            результат.append({'путь': относительный, **сведения})
    посетить(корень)
    return результат


def снимок_гита(корень):
    требовать(гит(корень, 'rev-parse', '--show-toplevel').decode().strip() == str(корень), 'иной checkout')
    ветка = гит(корень, 'symbolic-ref', 'HEAD').decode().strip()
    требовать(ветка.startswith('refs/heads/codex/'), 'нужна собственная codex-ветка')
    владельцы = [э for э in гит(корень, 'worktree', 'list', '--porcelain').decode().split('\n\n')
        if 'branch ' + ветка in э.splitlines()]
    требовать(len(владельцы) == 1 and владельцы[0].splitlines()[0] == 'worktree ' + str(корень),
        'не доказано единственное дерево ref')
    требовать(гит(корень, 'rev-parse', '--is-shallow-repository').strip() == b'false', 'неполная история')
    индекс = точный(гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index').decode().strip())
    return {'HEAD': гит(корень, 'rev-parse', 'HEAD').decode().strip(), 'ref': ветка,
        'индекс': файл(индекс)[0]}


class ЗагрузчикИсходника(importlib.abc.Loader):
    def __init__(сам, путь, данные):
        сам.путь = путь
        сам.данные = данные

    def create_module(сам, описание):
        return None

    def exec_module(сам, модуль):
        модуль.__file__ = str(сам.путь)
        exec(compile(сам.данные, str(сам.путь), 'exec'), модуль.__dict__)
        модуль._архив_отпечаток_исходника = хэш(сам.данные)


def _закрытое_описание(имя, расположение, *аргументы, **параметры):
    описание = _ОПИСАНИЕ(имя, расположение, *аргументы, **параметры)
    if _КОНТУР is not None and расположение is not None:
        путь = Path(расположение).resolve()
        if путь.is_relative_to(_КОНТУР['корень']):
            требовать(путь in _КОНТУР['исходники'], 'незакреплённый исполняемый вход K')
            описание.loader = ЗагрузчикИсходника(путь, _КОНТУР['исходники'][путь])
    return описание


class ПоискЗакрытогоКода(importlib.abc.MetaPathFinder):
    def find_spec(сам, fullname, path=None, target=None):
        описание = importlib.machinery.PathFinder.find_spec(fullname, path, target)
        if описание is None:
            return None
        if описание.origin is not None:
            путь = Path(описание.origin).resolve()
            if путь.is_relative_to(_КОНТУР['корень']):
                требовать(путь in _КОНТУР['исходники'], 'незакреплённый модуль или bytecode K')
                описание.loader = ЗагрузчикИсходника(путь, _КОНТУР['исходники'][путь])
                return описание
        elif описание.submodule_search_locations:
            требовать(not any(Path(э).resolve().is_relative_to(_КОНТУР['корень'])
                for э in описание.submodule_search_locations), 'незакреплённый namespace K')
        return None


def _проверить_импорты():
    имена_проекта = {п.stem for п in _КОНТУР['исходники'] if п.parent.name == 'scripts'}
    for имя_модуля, модуль in list(sys.modules.items()):
        имя = getattr(модуль, '__file__', None)
        if имя is None:
            continue
        путь = Path(имя).resolve()
        if имя_модуля in имена_проекта:
            требовать(путь in _КОНТУР['исходники'], 'ранее загружен чужой проектный модуль')
        if путь.is_relative_to(_КОНТУР['корень']):
            требовать(путь in _КОНТУР['исходники'] and getattr(модуль, '_архив_отпечаток_исходника', None)
                == хэш(_КОНТУР['исходники'][путь]), 'чужая ранее загруженная зависимость K')


def код(описание):
    global _КОНТУР
    поля(описание, {'корень', 'коммит'})
    требовать(файл(точный(str(_СВОЙ_ИСХОДНИК)))[0]['sha256'] == _СВОЙ_ОТПЕЧАТОК, 'изменён загруженный исходник перехода')
    корень = точный(описание['корень'])
    требовать(описание['коммит'] == КОММИТ_КОДА
        and гит(корень, 'rev-parse', 'HEAD').decode().strip() == КОММИТ_КОДА, 'иной принятый код')
    состав = []
    исходники = {}
    for строка in гит(корень, 'ls-tree', '-rz', КОММИТ_КОДА, '--', 'Инструменты').split(b'\0'):
        if not строка:
            continue
        заголовок, имя = строка.split(b'\t', 1)
        # Чужие SKILL/AGENTS и прочий Markdown не читаются даже для SHA.
        # Исполняемый контур — исходники и машинные ресурсы, не инструкции.
        if имя.decode().endswith('.md'):
            continue
        режим, тип, объект = заголовок.split()
        требовать(тип == b'blob' and режим in {b'100644', b'100755'}, 'неподдержанный вход кода')
        путь = точный(str(корень / имя.decode()))
        сведения, данные = файл(путь)
        фактический = hashlib.sha1(b'blob ' + str(len(данные)).encode() + b'\0' + данные).hexdigest().encode()
        требовать(фактический == объект and bool(сведения['режим'] & 0o111) == (режим == b'100755'), 'дрейф кода')
        состав.append({'путь': имя.decode(), 'объект': объект.decode(), 'режим': режим.decode()})
        if путь.suffix == '.py':
            исходники[путь] = данные
    требовать(bool(состав), 'пустой контур кода')
    каталог = str(корень / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts')
    if _КОНТУР is None:
        _КОНТУР = {'корень': корень / 'Инструменты', 'исходники': исходники}
        _проверить_импорты()
        importlib.util.spec_from_file_location = _закрытое_описание
        sys.meta_path.insert(0, ПоискЗакрытогоКода())
    else:
        требовать(_КОНТУР['корень'] == корень / 'Инструменты' and _КОНТУР['исходники'] == исходники,
            'смешаны или изменились code roots')
        _проверить_импорты()
    if каталог not in sys.path:
        sys.path.insert(0, каталог)
    этап = importlib.import_module('подготовка_этапа_коммита')
    обычное = importlib.import_module('обычное_поручение')
    генератор = importlib.import_module('подготовка_дочернего_поручения')
    _проверить_импорты()
    return этап, обычное, генератор, {'коммит': КОММИТ_КОДА, 'sha256': хэш(байты(состав)),
        'файлов': len(состав), 'наложение_sha256': _СВОЙ_ОТПЕЧАТОК}


def терминальный(корень, источник, отчёты):
    каталог = источник / 'материалы/запуски-проверок'
    сессия = (источник / 'запрос.md').relative_to(корень).as_posix()
    записи = отчёты.прочитать_историю_проверок(каталог, сессия)
    требовать(bool(записи) and all(э['состояние'] == 'завершён' for _, э, _ in записи),
        'нужен завершённый этап с терминальными проверками')
    требовать(not (каталог / 'возобновление.json').exists(), 'переходный отчёт')
    отчёт = источник / 'отчёт.md'
    требовать('<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->' not in отчёт.read_text(), 'незавершённый смысловой отчёт')
    if (каталог / 'снимок.json').exists():
        отчёты.проверить_закрытое_состояние(отчёт, каталог / 'снимок.json', записи, сессия)
    else:
        текст = отчёт.read_text()
        начало, конец, маркер = отчёты.границы_управляемого_блока(текст)
        требовать(маркер == отчёты.ОТКРЫТЫЙ_МАРКЕР, 'неизвестная граница отчёта')
        контекст, содержимое = отчёты.текущий_контекст_проверок(корень, сессия, записи)
        требовать(текст[начало:конец] == отчёты.сформировать_блок_истории(записи, маркер, контекст, содержимое),
            'нужен точный терминальный предпросмотр')
    for путь in источник.rglob('*.jsonl'):
        _, данные = файл(путь)
        требовать(not данные or данные.endswith(b'\n'), 'незавершённый RAW')
        for строка in данные.splitlines():
            значение = json.loads(строка, object_pairs_hook=_пары)
            требовать(type(значение) is dict and значение.get('type') in
                {'session_meta', 'turn_context', 'response_item', 'event_msg', 'compacted'}
                and type(значение.get('payload')) is dict
                and значение.get('состояние') is None, 'активный или неизвестный RAW')


def _журнальные_входы(корень, источник, каркас):
    результат = {}
    for относительный in sorted(каркас._canonical_requests(корень).values()):
        путь = корень / относительный
        if путь.parent == источник:
            continue
        сведения, данные = файл(путь)
        результат[путь.relative_to(корень).as_posix()] = {'файл': сведения, 'base64': base64.b64encode(данные).decode()}
        отчёт = путь.with_name('отчёт.md')
        if отчёт.exists():
            результат[отчёт.relative_to(корень).as_posix()] = {'тип': метаданные(отчёт)}
    путь = корень / 'Журнал/README.md'
    сведения, данные = файл(путь)
    результат['Журнал/README.md'] = {'файл': сведения, 'base64': base64.b64encode(данные).decode()}
    return результат


def публичный_план(корень, источник, новый, команды, каркас):
    поля(новый, {'основа', 'метка', 'заголовок'})
    требовать(not os.path.lexists(точный(str(корень / 'Журнал' / новый['основа']), существует=False)),
        'J2 должен целиком отсутствовать до эффекта')
    текущие = каркас._canonical_requests(корень)
    требовать(источник.name in текущие and источник.name == max(текущие)
        and новый['основа'] > источник.name, 'первый срез требует последний J1 и более поздний J2')
    входы = _журнальные_входы(корень, источник, каркас)
    with tempfile.TemporaryDirectory() as временный:
        проекция = Path(временный).resolve()
        гит(проекция, 'init', '-q', '-b', 'codex/проекция-частного-архива')
        for имя, сведения in входы.items():
            цель = проекция / имя
            цель.parent.mkdir(parents=True, exist_ok=True)
            цель.write_bytes(base64.b64decode(сведения['base64']) if 'base64' in сведения else b'')
            цель.chmod(сведения.get('файл', сведения.get('тип'))['режим'])
        подготовленные, _ = каркас.подготовить_начало(проекция, новый['основа'], новый['метка'],
            новый['заголовок'], команды['координатор'], [э['текст'] for э in команды['команды']])
    результат = []
    for ф in подготовленные:
        имя = ф.path.as_posix()
        прежний = корень / имя
        результат.append({'путь': имя, 'режим': ф.mode, 'base64': base64.b64encode(ф.data).decode(),
            'sha256': хэш(ф.data), 'до': файл(прежний)[0] if прежний.exists() else None})
    return результат, входы


def _каталоги_назначений(корень, файлы):
    имена = {родитель for э in файлы for родитель in (корень / э['путь']).parents
        if родитель != корень and родитель.is_relative_to(корень)}
    return {путь.relative_to(корень).as_posix(): метаданные(точный(str(путь)))
        if os.path.lexists(путь) else None for путь in sorted(имена)}


def _команды(этап, вход):
    for источник in вход['источники']:
        if 'кэш' in источник:
            читатель = этап.коммит.сообщения
            кэш = читатель._кэш_прочитать(Path(источник['кэш']), источник['задача'])
            требовать(кэш is not None and кэш['реализация'] == читатель._РЕАЛИЗАЦИЯ
                and кэш['метка'] == читатель._метка(Path(источник['путь']).stat())
                and кэш['граница'] == источник['граница_снимка']['граница']
                and кэш['sha256'] == источник['граница_снимка']['sha256'], 'нет свежего штатного кэша команд')
    return этап.корневые_команды({'корень': вход['корень'], 'источники': вход['источники']})


def _ссылка_на_источник(корень, имя, данные, источник, каркас):
    if имя.endswith('.md'):
        текст = данные.decode()
        защищено = каркас._request_body_span(текст) if Path(имя).name == 'запрос.md' else None
        _, ссылки = каркас._markdown_link_tokens(текст)
        инструменты = каркас._link_tools()
        for ссылка in ссылки:
            if защищено is not None and защищено[0] <= ссылка.destination_start < защищено[1]:
                continue
            цель = инструменты.resolve_destination(ссылка, корень / имя, корень, PurePosixPath(имя))
            if цель.is_local and цель.target is not None and цель.target.is_relative_to(источник):
                return True
        return False
    if имя.endswith('.json') and источник.name.encode() in данные:
        значение = json.loads(данные, object_pairs_hook=_пары)
        # Область закреплённого ACT является историческим полномочием,
        # а не активной ссылкой Журнала; её оригинал не переписывается.
        return not (type(значение) is dict and значение.get('схема') == 'fum.поручение-дочерней-контрольной-точки.1')
    return False


def планировать(вход, поручение):
    поля(вход, {'схема', 'корень', 'источник', 'архив', 'код', 'поручение', 'источники', 'новый'})
    требовать(вход['схема'] == СХЕМА, 'неизвестная схема архива')
    корень = точный(вход['корень'])
    этап, обычное, генератор, сведения_кода = код(вход['код'])
    допуск = обычное.проверить(вход['поручение'], поручение)
    п = вход['поручение']
    требовать(п['корень'] == str(корень) and п['запрос'] == (PurePosixPath(вход['источник']) / 'запрос.md').as_posix(), 'чужой исходный этап')
    требовать(вход['источник'].startswith('Журнал/') and len(Path(вход['источник']).parts) == 2,
        'нужен точный собственный J1')
    источник = точный(str(корень / вход['источник']))
    идентификатор, ошибки = обычное.охват.СВЯЗНОСТЬ.codex_thread_id_from_request((источник / 'запрос.md').read_text())
    требовать(not ошибки and идентификатор == п['задача'], 'чужой владелец запроса J1')
    требовать(not гит(корень, 'ls-files', '-z', '--', вход['источник']), 'J1 содержит tracked/staged файлы')
    требовать(not гит(корень, 'log', '--all', '--format=%H', '-1', '--', вход['источник']).strip(),
        'J1 ранее входил в Git-историю')
    архив = точный(вход['архив'], существует=False)
    вне_гита(архив)
    требовать(not архив.exists() and not архив.is_symlink(), 'назначение уже существует')
    родитель = метаданные(архив.parent)
    требовать(родитель['тип'] == 'каталог' and родитель['режим'] == 0o700
        and родитель['dev'] == источник.stat().st_dev, 'нужен частный родитель0700 на одной ФС')
    снимок = снимок_гита(корень)
    состав = снять_состав(источник)
    терминальный(корень, источник, этап.коммит.отчёты)
    команды = _команды(этап, вход)
    требовать(all(э['задача'] == п['задача'] for э in команды), 'чужие человеческие команды')
    файлы, журнальные = публичный_план(корень, источник, вход['новый'],
        {'координатор': п['задача'], 'команды': команды}, этап.каркас)
    акт = обычное.прочитать_акт(корень, поручение)
    требовать(вход['источник'] + '/' in акт['область'], 'нужен явный ACT-prefix целого J1')
    # Эффект над J1 — один rename корневого каталога; скрытые потомки
    # читаются и сохраняются по полному отдельно выбранному манифесту.
    обычное.проверить_область(корень, акт['область'], [п['запрос'], *[э['путь'] for э in файлы]])
    разрешённые = {э['путь'] for э in файлы}
    for имя in гит(корень, 'ls-files', '-z', '--cached', '--others', '--exclude-standard').decode().split('\0'):
        if not имя or имя.startswith(вход['источник'] + '/') or имя in разрешённые:
            continue
        путь = корень / имя
        if путь.is_file() and not путь.is_symlink():
            требовать(not _ссылка_на_источник(корень, имя, путь.read_bytes(), источник, этап.каркас),
                'внешняя ссылка на J1 вне плана')
    требовать(all(not _ссылка_на_источник(корень, э['путь'], base64.b64decode(э['base64']), источник, этап.каркас)
        for э in файлы), 'план сохранил активную ссылку J1')
    публикация = генератор.публикация(корень, {э['путь']: base64.b64decode(э['base64']) for э in файлы})
    требовать(снимок_гита(корень) == снимок and снять_состав(источник) == состав
        and _журнальные_входы(корень, источник, этап.каркас) == журнальные, 'дрейф подготовки')
    return {'схема': СХЕМА, 'вход_sha256': хэш(байты(вход)), 'состав': состав,
        'снимок': снимок, 'родитель_архива': родитель, 'код': сведения_кода,
        'допуск': допуск, 'команды': команды, 'публичные_файлы': файлы,
        'журнальные_входы': журнальные, 'каталоги_назначений': _каталоги_назначений(корень, файлы), 'публикация': публикация,
        'координатор': п['задача'], 'исполнитель': п['исполнитель']}


def _синхронизировать(путь):
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def _записать(путь, данные, режим=0o600, новый=False):
    if новый:
        дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, режим)
        with os.fdopen(дескриптор, 'wb') as поток:
            поток.write(данные)
            поток.flush()
            os.fsync(поток.fileno())
    else:
        дескриптор, имя = tempfile.mkstemp(prefix='.архив-', dir=путь.parent)
        временный = Path(имя)
        try:
            with os.fdopen(дескриптор, 'wb') as поток:
                os.fchmod(поток.fileno(), режим)
                поток.write(данные)
                поток.flush()
                os.fsync(поток.fileno())
            os.replace(временный, путь)
        finally:
            if временный.exists():
                временный.unlink()
    _синхронизировать(путь.parent)


def _перенести_исключительно(источник, архив):
    библиотека = ctypes.CDLL(None, use_errno=True)
    if sys.platform == 'darwin':
        функция = библиотека.renamex_np
        функция.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint]
        итог = функция(os.fsencode(источник), os.fsencode(архив), 4)
    elif sys.platform.startswith('linux') and hasattr(библиотека, 'renameat2'):
        функция = библиотека.renameat2
        функция.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
        итог = функция(-100, os.fsencode(источник), -100, os.fsencode(архив), 1)
    else:
        raise ValueError('исключительное атомарное перемещение не поддержано')
    if итог != 0:
        raise OSError(ctypes.get_errno(), 'атомарное перемещение отказало')


def _публично_записать(корень, элемент):
    цель = точный(str(корень / элемент['путь']), существует=False)
    дескриптор = os.open(корень, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        for имя in цель.relative_to(корень).parts[:-1]:
            try:
                следующий = os.open(имя, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=дескриптор)
            except FileNotFoundError:
                os.mkdir(имя, 0o755, dir_fd=дескриптор)
                os.fsync(дескриптор)
                следующий = os.open(имя, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=дескриптор)
            с = os.fstat(следующий)
            требовать(с.st_uid == os.getuid() and not (с.st_mode & 0o7022), 'чужой каталог назначения')
            os.close(дескриптор)
            дескриптор = следующий
        имя = цель.name
        данные = base64.b64decode(элемент['base64'])
        if элемент['до'] is None:
            файл_назначения = os.open(имя, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW,
                элемент['режим'], dir_fd=дескриптор)
            временное_имя = None
        else:
            временное_имя = '.архив-' + str(uuid.uuid4())
            файл_назначения = os.open(временное_имя, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW,
                элемент['режим'], dir_fd=дескриптор)
        try:
            with os.fdopen(файл_назначения, 'wb') as поток:
                os.fchmod(поток.fileno(), элемент['режим'])
                поток.write(данные)
                поток.flush()
                os.fsync(поток.fileno())
            if временное_имя is not None:
                os.replace(временное_имя, имя, src_dir_fd=дескриптор, dst_dir_fd=дескриптор)
            os.fsync(дескриптор)
        finally:
            if временное_имя is not None:
                with contextlib.suppress(FileNotFoundError):
                    os.unlink(временное_имя, dir_fd=дескриптор)
    finally:
        os.close(дескриптор)


def _выбор(план, выбор):
    поля(выбор, {'схема', 'план_sha256', 'координатор', 'исполнитель', 'завершён_и_нет_писателей', 'поручение'})

#!/usr/bin/env python3
"""CLI entry point for the request-folder layout automation."""

import hashlib
import argparse
import os
from pathlib import Path
import stat
import sys

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

from request_folder_layout import main as прежняя_главная


def обычная_пара(аргументы):
    """Явный версионный путь; P.1 и прежний CLI сохраняют своё поведение."""
    корень_инструментов = Path(__file__).resolve().parents[2]
    sys.path.insert(0, str(корень_инструментов / 'fum-svyaznostj-rabochej-sessii/scripts'))
    import подготовка_этапа_коммита as фасад
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('действие', choices=['обычная-пара-план', 'обычная-пара-установить'])
    разбор.add_argument('--repo-root', required=True)
    разбор.add_argument('--вход', required=True)
    разбор.add_argument('--выбранный-состав', required=True)
    разбор.add_argument('--план', required=True)
    разбор.add_argument('--sha256')
    п = разбор.parse_args(аргументы)
    try:
        вход = фасад.прочитать(п.вход)
        фасад.требовать(фасад._независимый_вход(вход), 'нужен явный фасад независимой точки .1')
        контекст = фасад._контекст_независимого_фасада(вход, п.выбранный_состав)
        корень = фасад._независимый_журнал().журнал().физический_корень(п.repo_root)
        фасад.требовать(str(корень) == контекст['параметры']['корень'], 'чужой физический корень CLI')
        файл = фасад.приватный(п.план, существует=п.действие != 'обычная-пара-план', режим=0o400)
        if п.действие == 'обычная-пара-план':
            фасад.требовать(п.sha256 is None and not os.path.lexists(файл), 'нужен новый план без входного SHA')
            план = фасад.построить_план(вход, выбранный_состав=п.выбранный_состав)
            данные = фасад.байты(план)
            with os.fdopen(os.open(файл, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o400), 'wb') as поток:
                поток.write(данные); поток.flush(); os.fsync(поток.fileno())
            итог = {'схема': 'fum.предпросмотр-обычной-пары.1', 'план_sha256': фасад.хэш(данные),
                'файлов_для_установки': 2}
        else:
            данные = файл.read_bytes()
            фасад.требовать(п.sha256 == фасад.хэш(данные), 'подмена SHA immutable плана')
            план = фасад.коммит.сообщения._разобрать(данные)
            фасад.требовать(type(план) is dict
                and план.get('схема') == фасад.СХЕМА_НЕЗАВИСИМОГО_ПЛАНА
                and план.get('вход_sha256') == фасад.хэш(фасад.байты(вход)), 'чужой план собственной пары')
            открытая = контекст['параметры']['контракт_журнала']['открытая']
            наличие = [os.path.lexists(корень / ф['путь']) for ф in открытая['файлы']]
            if not any(наличие):
                фасад.требовать(фасад.построить_план(вход, выбранный_состав=п.выбранный_состав) == план,
                    'дрейф перед первой установкой CLI')
            else:
                фасад.требовать(all(наличие), 'частичная собственная пара')
                for ф in план['начало']:
                    путь = фасад._независимый_журнал().журнал().точный_путь(корень, ф['путь'], существует=True)
                    фасад.требовать(stat.S_ISREG(путь.lstat().st_mode)
                        and stat.S_IMODE(путь.lstat().st_mode) == ф['режим']
                        and фасад.хэш(путь.read_bytes()) == ф['sha256'], 'повтор CLI отличается от начальной пары')
            итог = фасад._установить_новую_пару(вход, план, п.выбранный_состав)
            итог = {'схема': 'fum.установка-обычной-пары.1', 'результат': итог}
        print(фасад.байты(итог).decode(), end='')
        return 0
    except (ValueError, OSError, KeyError, TypeError, фасад.каркас.LayoutError) as ошибка:
        print('Ошибка: ' + str(ошибка), file=sys.stderr)
        return 1


def главная(аргументы=None):
    вход = sys.argv[1:] if аргументы is None else аргументы
    if вход and вход[0] in {'обычная-пара-план', 'обычная-пара-установить'}:
        return обычная_пара(вход)
    return прежняя_главная(аргументы)


if __name__ == "__main__":
    raise SystemExit(главная())

def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def канон(значение):
    return журнал.контракт.канон(значение)


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def поля(значение, имена):
    журнал.контракт.поля(значение, set(имена))


def физический_файл(имя):
    путь = Path(имя)
    требовать(путь.is_absolute() and путь == путь.resolve()
        and not any(п.is_symlink() for п in (путь, *путь.parents)), 'нефизический источник')
    состояние = путь.lstat()
    требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1
        and состояние.st_uid == os.geteuid(), 'необычный или чужой источник')
    return путь


def состояние(корень, запись):
    путь = журнал.точный_путь(корень, запись['путь'], существует=True)
    с = путь.lstat()
    требовать(stat.S_ISREG(с.st_mode) and с.st_nlink == 1, 'необычный физический выход')
    return {'sha256': хэш(путь.read_bytes()), 'режим': stat.S_IMODE(с.st_mode)}


def защищённые(корень):
    админ = Path(журнал._гит(корень, 'rev-parse', '--absolute-git-dir').decode().strip())
    общий = Path(журнал._гит(корень, 'rev-parse', '--git-common-dir').decode().strip())
    if not общий.is_absolute():
        общий = (корень / общий).resolve()
    требовать(not os.path.lexists(админ / 'index.lock'), 'индекс занят другим писателем')
    результат = []
    for путь in (админ / 'index', общий / 'config', админ / 'config.worktree'):
        запись = {'путь': str(путь), 'состояние': None}
        if os.path.lexists(путь):
            физический_файл(путь)
            с = путь.stat()
            запись['состояние'] = {'sha256': хэш(путь.read_bytes()), 'режим': stat.S_IMODE(с.st_mode),
                'устройство': с.st_dev, 'inode': с.st_ino, 'mtime_ns': с.st_mtime_ns}
        результат.append(запись)
    return результат


def проверить_поручение(вход, выбор, акт):
    поля(выбор, ('источник', 'позиция', 'префикс', 'текст_sha256'))
    требовать(выбор['источник'] == вход['нативный_источник'], 'подменён выбранный native источник')
    путь = физический_файл(выбор['источник'])
    нативное = поручение.постановка.прочитать_нативное_поручение(str(путь), кодирование='буквальный')
    требовать(нативное['отправитель'] == вход['координатор']
        and выбор['префикс'] == нативное['источник']
        and выбор['текст_sha256'] == акт['хэш_нативного_поручения'] == хэш(нативное['текст'].encode()),
        'подменены native literal или firstprompt')
    позиция = выбор['позиция']
    поля(позиция, ('начало', 'конец', 'sha256'))
    требовать(type(позиция['начало']) is int and type(позиция['конец']) is int
        and 0 <= позиция['начало'] < позиция['конец'] == нативное['источник']['граница'],
        'неверные границы первоначального native span')
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        байты = поток.read(позиция['конец'])
        строки = байты.splitlines(keepends=True)
        требовать(строки and байты.endswith(b'\n')
            and sum(map(len, строки[:-1])) == позиция['начало']
            and хэш(байты) == нативное['источник']['sha256']
            and хэш(строки[-1]) == позиция['sha256'], 'подменён сырой native span')
        запись = журнал._разобрать_данные(строки[-1])
        данные = запись.get('payload', {})
        требовать(запись.get('type') == 'response_item'
            and данные.get('type') == 'function_call_output' and данные.get('name') == 'create_thread',
            'выбран не первый нативный транспорт поручения')
        поток.seek(0)
        после = путь.stat()
        требовать((до.st_dev, до.st_ino) == (после.st_dev, после.st_ino)
            and поток.read(len(байты)) == байты, 'native источник изменился при чтении')
    return нативное


def контекст(вход, выбранное_поручение, выбранный_переход, *, временные=()):
    поля(вход, ('схема', 'корень', 'исполнитель', 'координатор', 'ветка',
        'нативный_источник', 'журнал', 'основа', 'выбранное_поручение'))
    требовать(вход['схема'] == СХЕМА_ВХОДА
        and вход['выбранное_поручение'] == выбранное_поручение, 'нет независимого выбора ACT')
    поля(выбранный_переход, ('схема', 'источники', 'до', 'подготовка', 'готовность',
        'квитанция', 'форма', 'поручение'))
    выбор = выбранный_переход
    требовать(выбор['схема'] == СХЕМА_ВЫБОРА and выбор['форма'] in ('буквальная', 'маркированная'),
        'неизвестная явно выбранная форма прежнего P.1')
    корень = журнал.физический_корень(Path(вход['корень']))
    журнал.контракт.путь(вход['журнал'])
    требовать(вход['журнал'].startswith('Журнал/') and вход['журнал'].count('/') == 1,
        'нужна собственная папка Журнала')
    пути = [(PurePosixPath(вход['журнал']) / имя).as_posix() for имя in ('запрос.md', 'отчёт.md')]
    поля(вход['основа'], ('коммит', 'дерево'))
    параметры = {'схема': 'fum.создание-коммита.7', 'режим': 'контрольная-точка',
        'корень': str(корень), 'задача': вход['координатор'], 'исполнитель': вход['исполнитель'],
        'ветка': вход['ветка'], 'выбранное_поручение': вход['выбранное_поручение'],
        'источник_модели': вход['нативный_источник'], 'исходный_коммит': вход['основа']['коммит'],
        'разрешённые_цели': пути, 'запрос': пути[0],
        'история_модели': (PurePosixPath(вход['журнал']) / 'материалы' / 'история-модели.json').as_posix()}
    привязка = поручение.проверить(параметры, выбранное_поручение)
    акт = поручение.прочитать_акт(корень, выбранное_поручение)
    требовать(журнал._гит(корень, 'rev-parse', 'HEAD^{tree}').decode().strip() == вход['основа']['дерево'],
        'подменено выбранное дерево исходного HEAD')
    _, _, грязные = поручение.охват.прочитать_статус(корень)
    поручение.проверить_область(корень, акт['область'], [*пути, *[п for п in грязные if п not in временные]])
    требовать(not журнал._гит(корень, '--literal-pathspecs', 'ls-tree', '-z', 'HEAD', '--', *пути),
        'пара уже закреплена в HEAD')
    требовать(type(выбор['до']) is list and len(выбор['до']) == len(пути), 'нужна полная прежняя пара')
    for путь, запись in zip(пути, выбор['до'], strict=True):
        поля(запись, ('путь', 'sha256', 'режим'))
        требовать(запись['путь'] == путь and type(запись['режим']) is int
            and запись['режим'] == 0o644 and type(запись['sha256']) is str
            and блоки.ХЭШ.fullmatch(запись['sha256']), 'неверный независимый выбор прежней пары')
        требовать(состояние(корень, запись)['режим'] == запись['режим'], 'изменён режим собственной пары')
    операционные = [выбор[имя] for имя in ('подготовка', 'готовность', 'квитанция')]
    требовать(len(set(операционные)) == len(операционные), 'операционные результаты должны различаться')
    for имя in операционные:
        путь = Path(имя)
        требовать(путь.is_absolute() and путь == путь.resolve()
            and not any(п.is_symlink() or os.path.lexists(п / '.git') for п in путь.parents)
            and stat.S_IMODE(путь.parent.stat().st_mode) == 0o700 and not os.path.lexists(путь),
            'переход разрешён только до prepare/READY/квитанции')
    отчёты = подготовка.коммит.отчёты
    _, запрос, отчёт, запуски, сеанс = отчёты.разрешить_сессию(корень, пути[0])
    try:
        рендер._проверки_в_отчёте(отчёт.read_bytes(), отчёты)
        отчёты.запретить_действие_при_возобновлении(запуски, 'переход происхождения пары')
        требовать(not os.path.lexists(запуски / 'снимок.json'), 'закрытый снимок не меняется')
        if запуски.exists():
            записи = отчёты.прочитать_записи(запуски, сеанс, разрешить_раунды=True)
            требовать(all(з['состояние'] == 'завершён' for _, з, _ in записи), 'активный RAW запрещает переход')
    except отчёты.ОшибкаОтчёта as ошибка:
        raise ValueError(str(ошибка)) from ошибка
    рендер._проверить_владение(запрос.read_bytes(), вход['координатор'])
    требовать(type(выбор['источники']) is list and выбор['источники'], 'нужны непустые источники ROOT')
    for источник in выбор['источники']:
        физический_файл(источник['путь'])
    команды = подготовка.корневые_команды({'корень': str(корень), 'источники': выбор['источники']})
    требовать(команды and all(з['задача'] == вход['координатор'] for з in команды),
        'нужен полный непустой выбранный набор человеческих оригиналов ROOT')
    нативное = проверить_поручение(вход, выбор['поручение'], акт)
    return корень, привязка, защищённые(корень), команды, нативное


def построить_план(вход, *, выбранное_поручение, выбранный_переход, прежние=None):
    корень, привязка, защита, команды, нативное = контекст(вход,
        выбранное_поручение, выбранный_переход)
    выбор = выбранный_переход
    if прежние is None:
        прежние = [(корень / з['путь']).read_bytes() for з in выбор['до']]
    требовать(type(прежние) is list and len(прежние) == len(выбор['до']), 'нужны полные прежние байты')
    for запись, данные in zip(выбор['до'], прежние, strict=True):
        требовать(type(данные) is bytes and хэш(данные) == запись['sha256'], 'изменён прежний raw SHA пары')
    журнал._ресурсы()
    каркас = журнал.каркас
    основа = Path(вход['журнал']).name
    совпадение = каркас.SESSION_PATTERN.fullmatch(основа)
    требовать(совпадение is not None, 'неканоническая собственная папка')
    метка = совпадение.group('label'); заголовок = каркас._заголовок_из_метки(метка)
    _, шаблон, _ = каркас._каркас_начала(корень, основа, метка, заголовок,
        вход['координатор'], [з['текст'] for з in команды])
    def тело(сообщения):
        документ = каркас._request_document(основа, заголовок, None, None, сообщения,
            вход['координатор'], {}, шаблон).encode()
        а, б = рендер._секции(документ, рендер.РАЗДЕЛЫ_ЗАПРОСА)[0]['Текст запроса']
        return документ[а:б]
    запрос, отчёт = прежние
    а, б = рендер._секции(запрос, рендер.РАЗДЕЛЫ_ЗАПРОСА)[0]['Текст запроса']
    прежний_текст = нативное['текст']
    if выбор['форма'] == 'маркированная':
        прежний_текст = 'Первоначальное агентское поручение ROOT (не сообщение человека):\n\n' + прежний_текст
    требовать(запрос[а:б] == тело([прежний_текст]), 'прежняя форма содержит иной ввод; prefix не доказан')
    части = []
    for команда in команды:
        образец = тело([команда['текст']])
        требовать(образец.startswith(b'\n') and образец.endswith(b'\n\n'), 'неизвестные границы stock P.1')
        части.append(('<!-- FUM-INTAKE: ' + команда['экземпляр'] + ' -->\n\n').encode() + образец[1:-2])
    новый_запрос = запрос[:а] + b'\n' + b'\n\n'.join(части) + b'\n\n' + запрос[б:]
    событие = {'источник': {'задача': вход['исполнитель'], **выбор['поручение']['позиция']},
        'роль': 'наблюдение', 'текст': нативное['текст']}
    событие['идентификатор'] = хэш(канон({'поручение': выбранное_поручение,
        'первоначальное_поручение': выбор['поручение'], 'событие': событие}))
    новый_отчёт = рендер._поставить_границы(отчёт, рендер._положение(отчёт, True))
    if not any(строка.startswith('<!-- FUM-ЖУРНАЛ:') for _, _, строка in блоки.структурные_строки(новый_отчёт)):
        место = рендер._секции(новый_отчёт, рендер.РАЗДЕЛЫ_ОТЧЁТА)[0]['Решения и ограничения'][1]
        новый_отчёт = новый_отчёт[:место] + блоки.пустой_курсор() + b'\n' + новый_отчёт[место:]
    новый_отчёт = блоки.дополнить_журнал(новый_отчёт, [событие])
    рендер._журнал_до_рендера(новый_отчёт, рендер._положение(новый_отчёт, True))
    рендер._проверки_в_отчёте(новый_отчёт, подготовка.коммит.отчёты)
    выходы = [{'путь': з['путь'], 'режим': з['режим'], 'sha256': хэш(д),
        'содержимое': base64.b64encode(д).decode()} for з, д in
        zip(выбор['до'], (новый_запрос, новый_отчёт), strict=True)]
    return {'схема': СХЕМА_ПЛАНА, 'вход': вход, 'выбор': выбор,
        'прежние': [base64.b64encode(д).decode() for д in прежние], 'выходы': выходы,
        'команды': команды, 'событие': событие, 'привязка_поручения': привязка, 'защищённые': защита}


class НеполныйПереход(ValueError):
    def __init__(сам, причина, записано, возможен_эффект):
        super().__init__('Неизвестный или частичный исход; чужие байты сохранены: ' + str(причина))
        сам.записано = записано
        сам.возможен_эффект = возможен_эффект


def записать_полностью(поток, данные):
    позиция = 0
    while позиция < len(данные):
        число = поток.write(memoryview(данные)[позиция:])
        требовать(type(число) is int and 0 < число <= len(данные) - позиция, 'запись не продвигается')
        позиция += число


def применить_план(вход, план, *, ожидаемый_хэш, выбранное_поручение, выбранный_переход):
    требовать(хэш(канон(план)) == ожидаемый_хэш, 'подменён immutable план')
    прежние = [base64.b64decode(д, validate=True) for д in план['прежние']]
    пересчитан = построить_план(вход, выбранное_поручение=выбранное_поручение,
        выбранный_переход=выбранный_переход, прежние=прежние)
    требовать(канон(план) == канон(пересчитан), 'план отличается от независимого полного выбора')
    корень = Path(вход['корень'])
    старые = [{к: з[к] for к in ('sha256', 'режим')} for з in выбранный_переход['до']]
    конечные = [{к: з[к] for к in ('sha256', 'режим')} for з in план['выходы']]
    def состояния():
        return [состояние(корень, з) for з in план['выходы']]
    def результат():
        требовать(состояния() == конечные, 'неполный readback собственной пары')
        подготовка.коммит.сверить_тексты({'корень': str(корень), 'запрос': план['выходы'][0]['путь']}, план['команды'])
        события = блоки.прочитать_журнал((корень / план['выходы'][1]['путь']).read_bytes())
        требовать(события.count(план['событие']) == 1, 'не сохранено единственное агентское событие')
    def сверить(номер, временные=()):
        _, привязка, защита, команды, _ = контекст(вход, выбранное_поручение,
            выбранный_переход, временные=временные)
        требовать(привязка == план['привязка_поручения'] and защита == план['защищённые']
            and канон(команды) == канон(план['команды']), 'контекст изменился')
        требовать(состояния() == конечные[:номер] + старые[номер:], 'пара изменилась до замены')
    if состояния() == конечные:
        результат()
        сверить(len(конечные))
        return {'схема': 'fum.результат-перехода-происхождения-пары.1', 'записано': 0}
    требовать(состояния() == старые, 'неизвестный или смешанный исход; автоматический повтор запрещён')
    записано = 0; попытка = False
    try:
        for номер, выход in enumerate(план['выходы']):
            сверить(номер)
            путь = журнал.точный_путь(корень, выход['путь'], существует=True)
            дескриптор, имя = tempfile.mkstemp(prefix='.происхождение-пары-', dir=путь.parent)
            временный = Path(имя)
            try:
                данные = base64.b64decode(выход['содержимое'], validate=True)
                требовать(хэш(данные) == выход['sha256'], 'подменены выходные байты')
                with os.fdopen(дескриптор, 'wb', buffering=0) as поток:
                    записать_полностью(поток, данные)
                    os.fchmod(поток.fileno(), выход['режим']); os.fsync(поток.fileno())
                сверить(номер, (временный.relative_to(корень).as_posix(),))
                попытка = True
                os.replace(временный, путь)
                записано += 1; попытка = False
                каталог = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
                try:
                    os.fsync(каталог)
                finally:
                    os.close(каталог)
            finally:
                if os.path.lexists(временный):
                    временный.unlink()
        результат()
        сверить(len(конечные))
    except (OSError, ValueError, RuntimeError) as ошибка:
        raise НеполныйПереход(ошибка, записано, попытка or bool(записано)) from ошибка
    return {'схема': 'fum.результат-перехода-происхождения-пары.1', 'записано': записано}


def прочитать_приватный(имя, *, ожидаемый_хэш=None):
    путь = физический_файл(имя)
    требовать(stat.S_IMODE(путь.stat().st_mode) == 0o600
        and stat.S_IMODE(путь.parent.stat().st_mode) == 0o700
        and not any(os.path.lexists(п / '.git') for п in путь.parents), 'нужен приватный файл вне Git')
    данные = путь.read_bytes()
    требовать(ожидаемый_хэш is None or хэш(данные) == ожидаемый_хэш, 'подмена SHA приватного входа')
    return журнал._разобрать_данные(данные)


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('действие', choices=('подготовить', 'применить'))
    разбор.add_argument('--вход', required=True)
    разбор.add_argument('--выбранное-поручение', required=True)
    разбор.add_argument('--выбранный-переход', required=True)
    разбор.add_argument('--выбор-sha256', required=True)
    разбор.add_argument('--план', required=True)
    разбор.add_argument('--план-sha256')
    п = разбор.parse_args()
    try:
        вход = прочитать_приватный(п.вход)
        требовать(Path.cwd() == Path(вход['корень']), 'CLI требует фактический собственный cwd')
        акт = прочитать_приватный(п.выбранное_поручение)
        выбор = прочитать_приватный(п.выбранный_переход, ожидаемый_хэш=п.выбор_sha256)
        if п.действие == 'подготовить':
            требовать(п.план_sha256 is None, 'новый план не принимает готовый SHA')
            план = построить_план(вход, выбранное_поручение=акт, выбранный_переход=выбор)
            путь = Path(п.план)
            требовать(путь.is_absolute() and путь == путь.resolve()
                and not any(а.is_symlink() or os.path.lexists(а / '.git') for а in путь.parents)
                and stat.S_IMODE(путь.parent.stat().st_mode) == 0o700, 'нужен новый приватный план вне Git')
            данные = канон(план)
            with os.fdopen(os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600), 'wb', buffering=0) as поток:
                записать_полностью(поток, данные); os.fsync(поток.fileno())
            каталог = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
            try:
                os.fsync(каталог)
            finally:
                os.close(каталог)
            требовать(прочитать_приватный(путь, ожидаемый_хэш=хэш(данные)) == план, 'неполный readback плана')
            итог = {'схема': СХЕМА_ПЛАНА, 'sha256': хэш(данные), 'целей': len(план['выходы'])}
        else:
            требовать(п.план_sha256 is not None, 'применение требует независимый SHA плана')
            план = прочитать_приватный(п.план, ожидаемый_хэш=п.план_sha256)
            требовать(хэш(канон(план)) == п.план_sha256, 'неканонический immutable план')
            итог = применить_план(вход, план, ожидаемый_хэш=п.план_sha256,
                выбранное_поручение=акт, выбранный_переход=выбор)
        print(json.dumps(итог, ensure_ascii=False))
        return 0
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as ошибка:
        print(json.dumps({'схема': 'fum.отказ-перехода-происхождения-пары.1',
            'причина': str(ошибка), 'автоматический_повтор': False,
            'записано': getattr(ошибка, 'записано', 0),
            'возможен_эффект': getattr(ошибка, 'возможен_эффект', False)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(главная())

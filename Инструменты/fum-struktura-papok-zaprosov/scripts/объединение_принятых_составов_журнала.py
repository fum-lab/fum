"""Точное объединение закрытых Журналов двух независимо выбранных коммитов.

Модуль не выбирает источники и не разрешает запись. Деревья объединённого
представления не получают вымышленного Git OID: для каталогов хранится None.
"""
import re

СХЕМА = 'fum.принятый-состав-обычного-журнала.2'


def проверить_коммиты(коммиты, контракт):
    контракт.требовать(type(коммиты) is list and len(коммиты) == 2
        and all(type(к) is str and re.fullmatch(r'[0-9a-f]{40}|[0-9a-f]{64}', к)
            for к in коммиты)
        and коммиты[0] != коммиты[1] and len(коммиты[0]) == len(коммиты[1]),
        'нужны два различных упорядоченных полных коммита')
    return list(коммиты)


def объединить_деревья(левое, правое, модуль):
    """Только область Журнала; остальные файлы не становятся принятыми."""
    контракт = модуль.контракт
    результат = {}
    for дерево in (левое, правое):
        for имя, запись in дерево.items():
            if имя != 'Журнал' and not имя.startswith('Журнал/'):
                continue
            режим, тип, объект = запись
            if имя in результат:
                прежняя = результат[имя]
                контракт.требовать(прежняя[:2] == (режим, тип)
                    and (тип == 'tree' or прежняя[2] == объект),
                    'конфликт закрытого Журнала: ' + имя)
            else:
                результат[имя] = (режим, тип, None if тип == 'tree' else объект)
    # В частности, запрещает коллизии регистра между разными источниками.
    модуль._проверить_структуру(результат)
    return результат


def дерево(корень, коммиты, модуль):
    проверить_коммиты(коммиты, модуль.контракт)
    деревья = []
    for коммит in коммиты:
        модуль.контракт.требовать(
            модуль._гит(корень, 'cat-file', '-t', коммит) == b'commit\n',
            'источник объединения не является коммитом')
        деревья.append(модуль._дерево_коммита(корень, коммит))
    return объединить_деревья(*деревья, модуль)


def состав(корень, коммиты, модуль):
    """Общие пары сохраняют левую приёмку; их содержание обязано совпасть."""
    проверить_коммиты(коммиты, модуль.контракт)
    # Проверяем не только пары, но и полный набор закрытых материалов и RAW.
    дерево(корень, коммиты, модуль)
    записи = {}
    for коммит in коммиты:
        источник = модуль.состав_принятого_дерева(корень, коммит)
        for запись in источник['записи']:
            имя = запись['журнал']
            if имя in записи:
                без_приёмки = lambda з: {к: в for к, в in з.items() if к != 'приёмка'}
                модуль.контракт.требовать(
                    без_приёмки(записи[имя]) == без_приёмки(запись),
                    'конфликт содержания общей пары: ' + имя)
            else:
                записи[имя] = запись
    return {'схема': СХЕМА, 'коммиты': list(коммиты),
        'записи': [записи[имя] for имя in sorted(записи)]}

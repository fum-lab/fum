"""Полная замена отмеченных областей и проверяемое добавление записей у курсора.

Это чистые преобразования байтов: установка файлов принадлежит транзакции карточки.
Хэши проверяют целостность сохранённого представления, а не полномочия его автора.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import публичное_представление_событий as публичные

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


МАРКЕР_БЛОКА = re.compile(r'^<!-- FUM-КАРТОЧКА:(НАЧАЛО|КОНЕЦ) ([а-яё][а-яё0-9-]*) -->$')
ОГРАДА = re.compile(r'^ {0,3}(`{3,}|~{3,})(.*)$')
ХЭШ = re.compile(r'^[0-9a-f]{64}$')
ИДЕНТИФИКАТОР_ЗАДАЧИ = re.compile(r'^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$')
НАЧАЛО_ЖУРНАЛА = '<!-- FUM-ЖУРНАЛ:НАЧАЛО -->\n'.encode()
НАЧАЛО_ЗАПИСИ = '<!-- FUM-ЖУРНАЛ:ЗАПИСЬ '.encode()
КОНЕЦ_ЗАПИСИ = '<!-- FUM-ЖУРНАЛ:КОНЕЦ-ЗАПИСИ -->\n'.encode()
МАРКЕР_КУРСОРА = re.compile(r'^<!-- FUM-ЖУРНАЛ:КУРСОР число=(0|[1-9][0-9]*); sha256=([0-9a-f]{64}) -->$')
ПУСТАЯ_ЦЕПОЧКА = hashlib.sha256(b'').hexdigest()


def канонические_байты(данные):
    return json.dumps(данные, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()


def структурные_строки(байты, *, состояние=None):
    """Вернуть байтовые границы видимых строк; ограды и обычные комментарии — данные."""
    текст = байты.decode('utf-8')
    ограда = None
    комментарий = False
    позиция = 0
    for строка in текст.splitlines(keepends=True):
        начало = позиция
        позиция += len(строка.encode())
        тело = строка.rstrip('\r\n')
        if ограда is not None:
            знак, длина = ограда
            if re.fullmatch(r' {0,3}' + re.escape(знак) + '{' + str(длина) + r',}[ \t]*', тело):
                ограда = None
            continue
        if not комментарий and тело.startswith(('<!-- FUM-КАРТОЧКА:', '<!-- FUM-ЖУРНАЛ:')):
            yield начало, позиция, тело
            continue
        видимое = []
        смещение = 0
        while смещение < len(тело):
            if комментарий:
                конец = тело.find('-->', смещение)
                if конец < 0:
                    break
                смещение = конец + 3
                комментарий = False
            else:
                начало_комментария = тело.find('<!--', смещение)
                if начало_комментария < 0:
                    видимое.append(тело[смещение:])
                    break
                видимое.append(тело[смещение:начало_комментария])
                смещение = начало_комментария + 4
                комментарий = True
        видимая_строка = ''.join(видимое)
        совпадение = ОГРАДА.fullmatch(видимая_строка)
        if совпадение and not (совпадение[1][0] == '`' and '`' in совпадение[2]):
            ограда = (совпадение[1][0], len(совпадение[1]))
            continue
        yield начало, позиция, видимая_строка
    if состояние is not None:
        состояние.update({'ограда': ограда, 'комментарий': комментарий})


def границы_блоков(байты):
    результат = {}
    открыт = None
    for начало, конец, строка in структурные_строки(байты):
        if not строка.startswith('<!-- FUM-КАРТОЧКА:'):
            continue
        совпадение = МАРКЕР_БЛОКА.fullmatch(строка)
        if совпадение is None:
            raise ValueError('Повреждённая строка управляемого блока')
        направление, имя = совпадение.groups()
        if направление == 'НАЧАЛО':
            if открыт is not None or имя in результат:
                raise ValueError('Вложенный или повторный управляемый блок')
            открыт = (имя, конец, b'\r\n' if байты[начало:конец].endswith(b'\r\n') else b'\n')
        else:
            if открыт is None or открыт[0] != имя:
                raise ValueError('Конец блока без соответствующего начала')
            результат[имя] = (открыт[1], начало, открыт[2])
            открыт = None
    if открыт is not None:
        raise ValueError('Управляемый блок не закрыт')
    return результат


def заменить_блоки(исходные: bytes, значения: dict[str, bytes]) -> bytes:
    if type(значения) is not dict:
        raise ValueError('Требуется явная карта выбранных блоков')
    границы = границы_блоков(исходные)
    if set(значения) - set(границы):
        raise ValueError('Выбранный управляемый блок отсутствует')
    замены = []
    for имя, тело in значения.items():
        if type(тело) is not bytes or (тело and not тело.endswith(b'\n')):
            raise ValueError('Тело блока должно быть байтами с завершающим переводом строки')
        состояние = {}
        for _, _, строка in структурные_строки(тело, состояние=состояние):
            if строка.startswith(('<!-- FUM-КАРТОЧКА:', '<!-- FUM-ЖУРНАЛ:')):
                raise ValueError('Вставка не вправе объявлять новые управляемые границы')
        if состояние['ограда'] is not None or состояние['комментарий']:
            raise ValueError('Тело блока оставляет незакрытую ограду или комментарий')
        начало, конец, перевод = границы[имя]
        тело = тело.replace(b'\r\n', b'\n')
        if b'\r' in тело:
            raise ValueError('Одиночный возврат каретки в генерируемом блоке запрещён')
        замены.append((начало, конец, тело.replace(b'\n', перевод)))
    результат = исходные
    for начало, конец, тело in sorted(замены, reverse=True):
        результат = результат[:начало] + тело + результат[конец:]
    ожидаемые = {}
    смещение = 0
    длины = {начало: len(тело) - (конец - начало) for начало, конец, тело in замены}
    for имя, (начало, конец, перевод) in sorted(границы.items(), key=lambda пара: пара[1][0]):
        новое_начало = начало + смещение
        смещение += длины.get(начало, 0)
        ожидаемые[имя] = (новое_начало, конец + смещение, перевод)
    if границы_блоков(результат) != ожидаемые:
        raise ValueError('Вставка сдвинула управляемые границы за пределы выбранных тел')
    return результат


def _проверить_событие(событие):
    if type(событие) is not dict or set(событие) != {'идентификатор', 'источник', 'роль', 'текст'}:
        raise ValueError('Неверные поля журнального события')
    источник = событие['источник']
    if (type(событие['идентификатор']) is not str or not ХЭШ.fullmatch(событие['идентификатор'])
            or type(источник) is not dict or set(источник) != {'задача', 'начало', 'конец', 'sha256'}
            or type(источник['задача']) is not str or not ИДЕНТИФИКАТОР_ЗАДАЧИ.fullmatch(источник['задача'])
            or type(источник['начало']) is not int or type(источник['конец']) is not int
            or not 0 <= источник['начало'] < источник['конец']
            or type(источник['sha256']) is not str or not ХЭШ.fullmatch(источник['sha256'])
            or type(событие['роль']) is not str or событие['роль'] not in {'пользователь', 'ассистент', 'наблюдение'}
            or type(событие['текст']) is not str or not событие['текст']):
        raise ValueError('Неверные значения журнального события')
    канонические_байты(событие)  # В том числе проверяет кодирование Unicode.


def _курсор(число, цепочка):
    return f'<!-- FUM-ЖУРНАЛ:КУРСОР число={число}; sha256={цепочка} -->\n'.encode()


def пустой_курсор() -> bytes:
    return НАЧАЛО_ЖУРНАЛА + _курсор(0, ПУСТАЯ_ЦЕПОЧКА)


def _отрисовать_запись(событие, предыдущий):
    _проверить_событие(событие)
    цепочка = hashlib.sha256(bytes.fromhex(предыдущий) + канонические_байты(событие)).hexdigest()
    текст = событие['текст'].encode()
    метаданные = {ключ: значение for ключ, значение in событие.items() if ключ != 'текст'}
    метаданные.update({'длина_текста': len(текст), 'предыдущий': предыдущий, 'цепочка': цепочка})
    длина = max([2] + [len(совпадение[0]) for совпадение in re.finditer(r'`+', событие['текст'])]) + 1
    ограда = b'`' * длина
    байты = (НАЧАЛО_ЗАПИСИ + канонические_байты(метаданные) + b' -->\n'
             + ограда + b'text\n' + текст + (b'' if текст.endswith(b'\n') else b'\n')
             + ограда + b'\n' + КОНЕЦ_ЗАПИСИ)
    return байты, цепочка


def _уникальные_поля(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ValueError('Повторное поле журнальной записи')
        результат[ключ] = значение
    return результат


def _прочитать_с_границами(байты):
    начало = []
    курсоры = []
    маркеры = []
    for а, б, строка in структурные_строки(байты):
        if строка.startswith('<!-- FUM-ЖУРНАЛ:'):
            маркеры.append((а, строка))
            if строка == НАЧАЛО_ЖУРНАЛА.decode().rstrip('\n'):
                начало.append((а, б))
            elif строка.startswith('<!-- FUM-ЖУРНАЛ:КУРСОР'):
                совпадение = МАРКЕР_КУРСОРА.fullmatch(строка)
                if not совпадение:
                    raise ValueError('Повреждённый курсор журнала')
                курсоры.append((а, б, int(совпадение[1]), совпадение[2]))
    if len(начало) != 1 or len(курсоры) != 1 or начало[0][1] > курсоры[0][0]:
        raise ValueError('Нужны единственные начало журнала и следующий за ним курсор')
    а, б = начало[0]
    в, г, число, хвост = курсоры[0]
    if байты[а:б] != НАЧАЛО_ЖУРНАЛА or байты[в:г] != _курсор(число, хвост):
        raise ValueError('Журнал должен иметь канонические строки границ')
    if any(позиция < а or позиция > в for позиция, _ in маркеры):
        raise ValueError('Журнальный маркер находится за пределами журнала')
    события = []
    идентификаторы = set()
    цепочка = ПУСТАЯ_ЦЕПОЧКА
    позиция = б
    while позиция < в:
        конец_метаданных = байты.find(b'\n', позиция, в)
        строка = байты[позиция:конец_метаданных]
        if конец_метаданных < 0 or not строка.startswith(НАЧАЛО_ЗАПИСИ) or not строка.endswith(b' -->'):
            raise ValueError('Повреждённое начало журнальной записи')
        данные = json.loads(строка[len(НАЧАЛО_ЗАПИСИ):-4], object_pairs_hook=_уникальные_поля)
        if (type(данные) is not dict
                or set(данные) != {'идентификатор', 'источник', 'роль', 'длина_текста', 'предыдущий', 'цепочка'}
                or type(данные['длина_текста']) is not int or данные['длина_текста'] < 1):
            raise ValueError('Неверные метаданные журнальной записи')
        конец_ограды = байты.find(b'\n', конец_метаданных + 1, в)
        if конец_ограды < 0 or not re.fullmatch(rb'`{3,}text', байты[конец_метаданных + 1:конец_ограды]):
            raise ValueError('Отсутствует ограда дословного текста записи')
        начало_текста = конец_ограды + 1
        конец_текста = начало_текста + данные['длина_текста']
        if конец_текста > в:
            raise ValueError('Длина текста выходит за курсор журнала')
        событие = {ключ: данные[ключ] for ключ in ('идентификатор', 'источник', 'роль')}
        событие['текст'] = байты[начало_текста:конец_текста].decode('utf-8')
        запись, следующая_цепочка = _отрисовать_запись(событие, цепочка)
        if байты[позиция:позиция + len(запись)] != запись or позиция + len(запись) > в:
            raise ValueError('Текст, метаданные или цепочка журнальной записи повреждены')
        if событие['идентификатор'] in идентификаторы:
            raise ValueError('Повторная уже сохранённая журнальная запись')
        идентификаторы.add(событие['идентификатор'])
        события.append(событие)
        цепочка = следующая_цепочка
        позиция += len(запись)
    if len(события) != число or цепочка != хвост:
        raise ValueError('Курсор не соответствует числу записей и хвосту цепочки')
    return события, (в, г, цепочка)


def прочитать_журнал(байты: bytes) -> list[dict]:
    return _прочитать_с_границами(байты)[0]


def дополнить_журнал(исходные: bytes, события: list[dict]) -> bytes:
    прежние, (начало, конец, цепочка) = _прочитать_с_границами(исходные)
    if type(события) is not list:
        raise ValueError('Требуется массив журнальных вставок')
    известные = {событие['идентификатор']: канонические_байты(событие) for событие in прежние}
    установленные = {событие['идентификатор']: событие for событие in прежние}
    новые = []
    for событие in события:
        _проверить_событие(событие)
        идентификатор = событие['идентификатор']
        байты = канонические_байты(событие)
        if идентификатор in известные:
            if известные[идентификатор] != байты and not (идентификатор in установленные
                    and публичные.проверить_повтор(установленные[идентификатор], событие)):
                raise ValueError('Прежний идентификатор получил другие данные')
            continue
        известные[идентификатор] = байты
        запись, цепочка = _отрисовать_запись(событие, цепочка)
        новые.append(запись)
    if not новые:
        return исходные
    результат = (исходные[:начало] + b''.join(новые)
                 + _курсор(len(известные), цепочка) + исходные[конец:])
    _прочитать_с_границами(результат)
    return результат

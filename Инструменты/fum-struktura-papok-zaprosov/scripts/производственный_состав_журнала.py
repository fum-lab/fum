class НеполныйПереход(ValueError):
    def __init__(сам, причина, записано, возможен_эффект):
        super().__init__('Переход не принят; чужие байты не откатывались: ' + str(причина))
        сам.записано = записано
        сам.возможен_эффект = возможен_эффект


def канон(значение):
    return контракт.канон(значение)


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def гит(корень, *аргументы, вход=None):
    return журнал._гит(корень, *аргументы, вход=вход)


def объект(корень, идентификатор, тип):
    данные = гит(корень, 'cat-file', тип, идентификатор)
    алгоритм = hashlib.sha1 if len(идентификатор) == 40 else hashlib.sha256
    требовать(алгоритм(тип.encode() + b' ' + str(len(данные)).encode() + b'\0' + данные).hexdigest()
        == идентификатор, 'подменён Git-объект выбранной основы')
    return данные


def выбранное_дерево(корень, выбор):
    контракт.поля(выбор, {'коммит', 'дерево'})
    for значение in выбор.values():
        поручение.история.полный_идентификатор(значение)
    данные = объект(корень, выбор['коммит'], 'commit')
    строки = данные.split(b'\n\n', 1)[0].splitlines()
    деревья = [строка.removeprefix(b'tree ').decode() for строка in строки if строка.startswith(b'tree ')]
    требовать(деревья == [выбор['дерево']], 'выбранное дерево не совпадает с коммитом')
    объект(корень, выбор['дерево'], 'tree')


def контекст(вход, выбранное_поручение, выбранная_основа, *, временные=()):
    контракт.поля(вход, {'схема', 'корень', 'исполнитель', 'координатор', 'ветка',
        'нативный_источник', 'журнал', 'основа', 'принятый_журнал', 'выбранное_поручение'})
    требовать(вход['схема'] == СХЕМА_ВХОДА, 'неизвестный вход производителя')
    требовать(канон(вход['выбранное_поручение']) == канон(выбранное_поручение),
        'копия ACT не заменяет независимый выбор')
    контракт.поля(выбранная_основа, {'схема', 'основа', 'принятый_журнал'})
    требовать(выбранная_основа['схема'] == 'fum.выбор-основы-производственного-журнала.1'
        and all(канон(вход[поле]) == канон(выбранная_основа[поле])
            for поле in ('основа', 'принятый_журнал')),
        'кандидат не заменяет независимо выбранные A/H')
    корень = журнал.физический_корень(Path(вход['корень']))
    контракт.путь(вход['журнал'])
    требовать(вход['журнал'].startswith('Журнал/') and вход['журнал'].count('/') == 1,
        'нужна собственная папка Журнала')
    параметры = {'схема': 'fum.создание-коммита.7', 'режим': 'контрольная-точка',
        'корень': str(корень), 'задача': вход['координатор'], 'исполнитель': вход['исполнитель'],
        'ветка': вход['ветка'], 'выбранное_поручение': вход['выбранное_поручение'],
        'источник_модели': вход['нативный_источник'], 'исходный_коммит': вход['основа']['коммит'],
        'разрешённые_цели': list(ЦЕЛИ),
        'запрос': (PurePosixPath(вход['журнал']) / 'запрос.md').as_posix(),
        'история_модели': (PurePosixPath(вход['журнал']) / 'материалы' / 'история-модели.json').as_posix()}
    привязка = поручение.проверить(параметры, выбранное_поручение)
    акт = поручение.прочитать_акт(корень, выбранное_поручение)
    выбранное_дерево(корень, вход['основа'])
    выбранное_дерево(корень, вход['принятый_журнал'])
    гит(корень, 'merge-base', '--is-ancestor', вход['принятый_журнал']['коммит'], вход['основа']['коммит'])
    _, _, пути = поручение.охват.прочитать_статус(корень)
    пути = [путь for путь in пути if путь not in временные]
    поручение.проверить_область(корень, акт['область'], [*ЦЕЛИ, *пути])
    каталог = Path(гит(корень, 'rev-parse', '--absolute-git-dir').decode().strip())
    общий = Path(гит(корень, 'rev-parse', '--git-common-dir').decode().strip())
    if not общий.is_absolute(): общий = (корень / общий).resolve()
    защищённые = [каталог / 'index', общий / 'config', каталог / 'config.worktree']
    снимок = [{'путь': str(п), 'sha256': хэш(п.read_bytes()) if п.exists() else None}
        for п in защищённые]
    return корень, акт, привязка, снимок


def покрыт(путь, область):
    return any((путь == граница[:-1] or путь.startswith(граница))
        if граница.endswith('/') else путь == граница for граница in область)


def деревья_пакетом(корень, деревья):
    идентификаторы = list(dict.fromkeys(деревья.values()))
    for идентификатор in идентификаторы: поручение.история.полный_идентификатор(идентификатор)
    if not идентификаторы: return {}
    сырой = гит(корень, 'cat-file', '--batch', вход=('\n'.join(идентификаторы) + '\n').encode())
    объекты = {}; позиция = 0
    for идентификатор in идентификаторы:
        конец = сырой.find(b'\n', позиция)
        требовать(конец >= позиция, 'усечён заголовок tree batch')
        поля = сырой[позиция:конец].decode().split()
        требовать(len(поля) == 3 and поля[:2] == [идентификатор, 'tree']
            and поля[2].isdigit() and str(int(поля[2])) == поля[2], 'неверный tree batch')
        размер = int(поля[2]); начало = конец + 1
        данные = сырой[начало:начало + размер]
        требовать(len(данные) == размер and сырой[начало + размер:начало + размер + 1] == b'\n',
            'усечены байты или разделитель tree batch')
        алгоритм = hashlib.sha1 if len(идентификатор) == 40 else hashlib.sha256
        требовать(алгоритм(b'tree ' + str(размер).encode() + b'\0' + данные).hexdigest() == идентификатор,
            'подменён OID дерева в пакете')
        объекты[идентификатор] = данные; позиция = начало + размер + 1
    требовать(позиция == len(сырой), 'лишний хвост tree batch')
    return {путь: объекты[идентификатор] for путь, идентификатор in деревья.items()}


def метаданные(с):
    return с.st_dev, с.st_ino, с.st_mode, с.st_size, с.st_mtime_ns, с.st_ctime_ns


def сверить_предки(корень, путь, каталоги):
    текущий = корень
    for часть in ('', *PurePosixPath(путь).parts[:-1]):
        if часть: текущий /= часть
        с = текущий.lstat()
        требовать(stat.S_ISDIR(с.st_mode) and метаданные(с) == каталоги[текущий],
            'предок изменился после полного структурного осмотра')


def файл_после_осмотра(корень, путь, каталоги):
    сверить_предки(корень, путь, каталоги)
    файл = корень / путь; до = файл.lstat()
    требовать(stat.S_ISREG(до.st_mode), 'тип файла изменился после осмотра')
    дескриптор = os.open(файл, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(дескриптор, 'rb') as поток:
        требовать(метаданные(os.fstat(поток.fileno())) == метаданные(до), 'файл подменён при открытии')
        данные = поток.read()
        требовать(метаданные(os.fstat(поток.fileno())) == метаданные(до), 'файл изменился при чтении')
    требовать(метаданные(файл.lstat()) == метаданные(до), 'адрес файла изменился при чтении')
    сверить_предки(корень, путь, каталоги)
    return данные, stat.S_IMODE(до.st_mode)


def память_журнала(корень, выбор, область):
    дерево = журнал._дерево_коммита(корень, выбор['коммит'])
    записи = {п: з for п, з in дерево.items() if п == 'Журнал' or п.startswith('Журнал/')}
    байты = журнал._прочитать_объекты(корень, {п: з[2] for п, з in записи.items() if з[1] == 'blob'})
    деревья = деревья_пакетом(корень, {п: з[2] for п, з in записи.items() if з[1] == 'tree'})
    живые = {п: з for п, з in журнал._живое_дерево(корень).items()
        if п == 'Журнал' or п.startswith('Журнал/')}
    каталоги = {корень: метаданные(корень.lstat())}
    for путь, запись in живые.items():
        if запись[1] == 'tree' and not покрыт(путь, область):
            файл = корень / путь; с = файл.lstat()
            требовать(stat.S_ISDIR(с.st_mode), 'каталог изменился после осмотра')
            каталоги[файл] = метаданные(с)
    доказательства = []
    for путь, (режим, тип, идентификатор) in sorted(записи.items()):
        данные = байты[путь] if тип == 'blob' else деревья[путь]
        доказательства.append({'путь': путь, 'тип': тип, 'режим': режим,
            'объект': идентификатор, 'sha256': хэш(данные), 'байты': len(данные)})
        if покрыт(путь, область): continue
        требовать(путь in живые and живые[путь][:2] == (режим, тип),
            'исчезла или изменила тип/режим прежняя память Журнала')
        if тип == 'blob':
            прочитано, физический_режим = файл_после_осмотра(корень, путь, каталоги)
            требовать(физический_режим == (0o755 if режим == '100755' else 0o644)
                and прочитано == данные, 'изменены прежние байты Журнала/материалов/RAW')
    пустые = {(PurePosixPath(п).parent / 'материалы').as_posix()
        for п in байты if PurePosixPath(п).name == 'отчёт.md'}
    for путь in set(живые) - set(записи):
        требовать(покрыт(путь, область) or путь in пустые
            and живые[путь][:2] == ('040000', 'tree') and not any((корень / путь).iterdir()),
            'посторонняя запись вне собственной папки Журнала')
    после = {п: з for п, з in журнал._живое_дерево(корень).items()
        if (п == 'Журнал' or п.startswith('Журнал/')) and not покрыт(п, область)}
    требовать(после == {п: з for п, з in живые.items() if not покрыт(п, область)},
        'структура или точные имена изменились после осмотра')
    требовать(all(метаданные(п.lstat()) == с for п, с in каталоги.items()),
        'каталоги изменились при проверке памяти')
    return {'коммит': выбор['коммит'], 'дерево': выбор['дерево'],
        'sha256': хэш(канон(доказательства)), 'записи': доказательства}


def предыдущее(корень, основа, путь):
    записи = журнал._дерево_коммита(корень, основа['коммит'])
    if путь not in записи: return None
    режим, тип, идентификатор = записи[путь]
    требовать((режим, тип) == ('100644', 'blob'), 'необычный принятый preimage выхода')
    данные = объект(корень, идентификатор, 'blob')
    return {'объект': идентификатор, 'sha256': хэш(данные), 'режим': 0o644}


def построить_план(вход, *, выбранное_поручение, выбранная_основа):
    корень, акт, привязка, защита = контекст(вход, выбранное_поручение, выбранная_основа)
    память = память_журнала(корень, вход['принятый_журнал'], акт['область'])
    состав = журнал.состав_принятого_дерева(корень, вход['принятый_журнал']['коммит'])
    навигация = журнал.построить_принятый_индекс(корень, состав)
    выходы = []
    for путь, данные in zip(ЦЕЛИ, (канон(состав), навигация['байты']), strict=True):
        журнал.точный_путь(корень, путь)
        выходы.append({'путь': путь, 'до': предыдущее(корень, вход['основа'], путь),
            'режим': 0o644, 'sha256': хэш(данные), 'байты': len(данные),
            'содержимое': base64.b64encode(данные).decode('ascii')})
    требовать(контекст(вход, выбранное_поручение, выбранная_основа)[2:] == (привязка, защита),
        'контекст изменился при построении')
    return {'схема': СХЕМА_ПЛАНА, 'вход': вход, 'привязка_поручения': привязка,
        'выбранная_основа': выбранная_основа,
        'защищённые': защита, 'память_журнала': память, 'состав': состав,
        'выходы': выходы, 'разрешение_установки': False}


def состояние(корень, выход):
    путь = журнал.точный_путь(корень, выход['путь'])
    if not os.path.lexists(путь): return None
    с = путь.lstat()
    требовать(stat.S_ISREG(с.st_mode) and с.st_nlink == 1, 'необычный физический выход')
    return {'sha256': хэш(путь.read_bytes()), 'режим': stat.S_IMODE(с.st_mode)}


def записать_полностью(поток, данные):
    позиция = 0
    while позиция < len(данные):
        число = поток.write(memoryview(данные)[позиция:])
        требовать(type(число) is int and 0 < число <= len(данные) - позиция,
            'временная запись не продвигается')
        позиция += число


def применить_план(вход, план, *, ожидаемый_sha256, выбранное_поручение, выбранная_основа):
    требовать(хэш(канон(план)) == ожидаемый_sha256, 'подменены байты плана')
    пересчитан = построить_план(вход, выбранное_поручение=выбранное_поручение,
        выбранная_основа=выбранная_основа)
    требовать(канон(пересчитан) == канон(план),
        'план не соответствует независимым входам и текущему контексту')
    корень = Path(вход['корень'])
    конечные = [{'sha256': з['sha256'], 'режим': з['режим']} for з in план['выходы']]
    прежние = [{к: з['до'][к] for к in ('sha256', 'режим')} if з['до'] is not None else None
        for з in план['выходы']]
    фактические = [состояние(корень, з) for з in план['выходы']]
    if фактические == конечные:
        return {'схема': 'fum.результат-производственного-состава-журнала.1',
            'план_sha256': ожидаемый_sha256, 'записано': 0, 'результат_проверен': True,
            'историческая_установка_подтверждена': False}
    требовать(фактические == прежние, 'неизвестный или частичный исход; автоматическое доведение запрещено')
    записано = 0
    for номер, выход in enumerate(план['выходы']):
        путь = журнал.точный_путь(корень, выход['путь'])
        требовать(путь.parent.is_dir(), 'родитель выхода должен уже существовать')
        данные = base64.b64decode(выход['содержимое'], validate=True)
        требовать(хэш(данные) == выход['sha256'], 'повреждены байты выхода')
        контекст(вход, выбранное_поручение, выбранная_основа)
        дескриптор, имя = tempfile.mkstemp(prefix='.производственный-состав-', dir=путь.parent)
        временный = Path(имя)
        try:
            with os.fdopen(дескриптор, 'wb', buffering=0) as поток:
                записать_полностью(поток, данные)
                os.fchmod(поток.fileno(), 0o644); os.fsync(поток.fileno())
            _, акт, привязка, защита = контекст(вход, выбранное_поручение, выбранная_основа,
                временные=(временный.relative_to(корень).as_posix(),))
            требовать(привязка == план['привязка_поручения'] and защита == план['защищённые'],
                'контекст изменился до replace')
            память_журнала(корень, вход['принятый_журнал'], акт['область'])
            ожидания = конечные[:номер] + прежние[номер:]
            требовать([состояние(корень, з) for з in план['выходы']] == ожидания,
                'выход изменился до replace')
            os.replace(временный, путь)
            дескриптор_каталога = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
            try: os.fsync(дескриптор_каталога)
            finally: os.close(дескриптор_каталога)
            записано += 1
        finally:
            if временный.exists(): временный.unlink()
    требовать([состояние(корень, з) for з in план['выходы']] == конечные, 'неполная установка')
    требовать(контекст(вход, выбранное_поручение, выбранная_основа)[2:] == (
        план['привязка_поручения'], план['защищённые']), 'контекст изменился после установки')
    return {'схема': 'fum.результат-производственного-состава-журнала.1',
        'план_sha256': ожидаемый_sha256, 'записано': записано, 'результат_проверен': True,
        'историческая_установка_подтверждена': True}


def прочитать_приватный(имя, *, ожидаемый_sha256=None):
    путь = Path(имя)
    требовать(путь.is_absolute() and путь == путь.resolve()
        and not any(п.is_symlink() for п in (путь, *путь.parents)), 'нефизический приватный вход')
    с = путь.stat()
    требовать(stat.S_ISREG(с.st_mode) and с.st_nlink == 1 and с.st_uid == os.getuid()
        and stat.S_IMODE(с.st_mode) in (0o400, 0o600)
        and stat.S_IMODE(путь.parent.stat().st_mode) == 0o700
        and not any(os.path.lexists(п / '.git') for п in путь.parents), 'небезопасный приватный вход')
    данные = путь.read_bytes()
    if ожидаемый_sha256 is not None:
        требовать(хэш(данные) == ожидаемый_sha256, 'подменён независимый приватный выбор')
    return журнал._разобрать_данные(данные)


def контур_происхождения(вход, выбранное_поручение, выбранная_основа, выбор, *, временные=()):
    import подготовка_этапа_коммита as подготовка
    import блоки_карточки as рендер
    import управляемые_блоки as блоки
    корень, акт, привязка, защита = контекст(вход, выбранное_поручение, выбранная_основа,
        временные=временные)
    контракт.поля(выбор, {'схема', 'источники', 'до', 'подготовка', 'готовность', 'квитанция'})
    требовать(выбор['схема'] == 'fum.выбор-происхождения-первого-журнала.1',
        'неизвестный конечный переход происхождения')
    пути = [(PurePosixPath(вход['журнал']) / имя).as_posix() for имя in ('запрос.md', 'отчёт.md')]
    поручение.проверить_область(корень, акт['область'], пути)
    требовать(not гит(корень, '--literal-pathspecs', 'ls-tree', '-z', 'HEAD', '--', *пути),
        'пара уже закреплена в HEAD')
    требовать(type(выбор['до']) is list and len(выбор['до']) == 2, 'нужна полная прежняя пара')
    for путь, запись in zip(пути, выбор['до'], strict=True):
        контракт.поля(запись, {'путь', 'sha256', 'режим'})
        требовать(запись['путь'] == путь and type(запись['режим']) is int
            and запись['режим'] == 0o644 and type(запись['sha256']) is str
            and блоки.ХЭШ.fullmatch(запись['sha256']), 'неверный прежний выбор пары')
        наблюдение = состояние(корень, запись)
        требовать(наблюдение is not None and наблюдение['режим'] == 0o644,
            'отсутствует пара или изменён её режим')
    for имя in ('подготовка', 'готовность', 'квитанция'):
        путь = Path(выбор[имя])
        требовать(путь.is_absolute() and путь == путь.resolve()
            and not any(п.is_symlink() or os.path.lexists(п / '.git') for п in путь.parents)
            and stat.S_IMODE(путь.parent.stat().st_mode) == 0o700
            and not os.path.lexists(путь), 'переход разрешён только до prepare/READY/квитанции')
    требовать(len({выбор[имя] for имя in ('подготовка', 'готовность', 'квитанция')}) == 3,
        'операционные результаты должны различаться')
    отчёты = подготовка.коммит.отчёты
    _, запрос, отчёт, запуски, сеанс = отчёты.разрешить_сессию(корень, пути[0])
    try:
        рендер._проверки_в_отчёте(отчёт.read_bytes(), отчёты)
        отчёты.запретить_действие_при_возобновлении(запуски, 'переход происхождения')
        требовать(not os.path.lexists(запуски / 'снимок.json'), 'закрытый снимок не меняется')
        if запуски.exists():
            записи = отчёты.прочитать_записи(запуски, сеанс, разрешить_раунды=True)
            требовать(all(з['состояние'] == 'завершён' for _, з, _ in записи),
                'активная проверка запрещает переход')
    except отчёты.ОшибкаОтчёта as ошибка:
        raise ValueError(str(ошибка)) from ошибка
    рендер._проверить_владение(запрос.read_bytes(), вход['координатор'])
    команды = подготовка.корневые_команды({'корень': str(корень), 'источники': выбор['источники']})
    требовать(len(команды) == 2 and all(з['задача'] == вход['координатор'] for з in команды),
        'нужны ровно два выбранных человеческих оригинала ROOT')
    нативное = поручение.постановка.прочитать_нативное_поручение(вход['нативный_источник'])
    требовать(нативное['отправитель'] == вход['координатор']
        and хэш(нативное['текст'].encode()) == акт['хэш_нативного_поручения'],
        'неверное происхождение первоначального literal')
    return корень, привязка, защита, команды, нативное


def построить_происхождение(вход, выбор, прежние, *, выбранное_поручение, выбранная_основа):
    import блоки_карточки as рендер
    import управляемые_блоки as блоки
    корень, привязка, защита, команды, нативное = контур_происхождения(
        вход, выбранное_поручение, выбранная_основа, выбор)
    if прежние is None:
        прежние = [(корень / з['путь']).read_bytes() for з in выбор['до']]
    требовать(type(прежние) is list and len(прежние) == 2, 'нужны точные старые байты пары')
    for запись, данные in zip(выбор['до'], прежние, strict=True):
        требовать(type(данные) is bytes and хэш(данные) == запись['sha256'], 'изменён прежний raw SHA пары')
    журнал._ресурсы()
    каркас = журнал.каркас
    основа = Path(вход['журнал']).name
    метка = каркас.SESSION_PATTERN.fullmatch(основа).group('label')
    заголовок = каркас._заголовок_из_метки(метка)
    _, шаблон, _ = каркас._каркас_начала(корень, основа, метка, заголовок,
        вход['координатор'], [з['текст'] for з in команды])
    def тело(сообщения):
        документ = каркас._request_document(основа, заголовок, None, None,
            сообщения, вход['координатор'], {}, шаблон).encode()
        а, б = рендер._секции(документ, рендер.РАЗДЕЛЫ_ЗАПРОСА)[0]['Текст запроса']
        return документ[а:б]
    старый_запрос, старый_отчёт = прежние
    рендер._проверить_владение(старый_запрос, вход['координатор'])
    а, б = рендер._секции(старый_запрос, рендер.РАЗДЕЛЫ_ЗАПРОСА)[0]['Текст запроса']
    требовать(старый_запрос[а:б] == тело([
        'Первоначальное агентское поручение ROOT (не сообщение человека):\n\n' + нативное['текст']]),
        'старый raw содержит иной ввод; его нельзя отбросить')
    части = []
    for команда in команды:
        образец = тело([команда['текст']])
        требовать(образец.startswith(b'\n') and образец.endswith(b'\n\n'), 'неизвестные границы P.1')
        части.append(('<!-- FUM-INTAKE: ' + команда['экземпляр'] + ' -->\n\n').encode() + образец[1:-2])
    новый_запрос = старый_запрос[:а] + b'\n' + b'\n\n'.join(части) + b'\n\n' + старый_запрос[б:]
    событие = {'источник': {'задача': вход['исполнитель'], 'начало': 0,
        'конец': нативное['источник']['граница'], 'sha256': нативное['источник']['sha256']},
        'роль': 'наблюдение', 'текст': нативное['текст']}
    событие['идентификатор'] = хэш(канон({'поручение': выбранное_поручение, 'событие': событие}))
    новый_отчёт = рендер._поставить_границы(старый_отчёт, рендер._положение(старый_отчёт, True))
    if not any(строка.startswith('<!-- FUM-ЖУРНАЛ:') for _, _, строка in блоки.структурные_строки(новый_отчёт)):
        место = рендер._секции(новый_отчёт, рендер.РАЗДЕЛЫ_ОТЧЁТА)[0]['Решения и ограничения'][1]
        новый_отчёт = новый_отчёт[:место] + блоки.пустой_курсор() + b'\n' + новый_отчёт[место:]
    новый_отчёт = блоки.дополнить_журнал(новый_отчёт, [событие])
    рендер._журнал_до_рендера(новый_отчёт, рендер._положение(новый_отчёт, True))
    import подготовка_этапа_коммита as подготовка
    рендер._проверки_в_отчёте(новый_отчёт, подготовка.коммит.отчёты)
    выходы = [{'путь': з['путь'], 'режим': з['режим'], 'sha256': хэш(данные),
        'содержимое': base64.b64encode(данные).decode()} for з, данные in
        zip(выбор['до'], (новый_запрос, новый_отчёт), strict=True)]
    return {'схема': 'fum.план-происхождения-первого-журнала.1', 'вход': вход,
        'выбор': выбор, 'прежние': [base64.b64encode(д).decode() for д in прежние],
        'выходы': выходы, 'команды': команды, 'событие': событие,
        'привязка_поручения': привязка, 'защищённые': защита}


def подготовить_происхождение(вход, *, выбранное_поручение, выбранная_основа, выбранный_переход):
    return построить_происхождение(вход, выбранный_переход, None,
        выбранное_поручение=выбранное_поручение, выбранная_основа=выбранная_основа)


def применить_происхождение(вход, план, *, ожидаемый_sha256, выбранное_поручение,
                            выбранная_основа, выбранный_переход):
    import подготовка_этапа_коммита as подготовка
    import управляемые_блоки as блоки
    требовать(хэш(канон(план)) == ожидаемый_sha256, 'подменён план происхождения')
    прежние = [base64.b64decode(д, validate=True) for д in план['прежние']]
    пересчитан = построить_происхождение(вход, выбранный_переход, прежние,
        выбранное_поручение=выбранное_поручение, выбранная_основа=выбранная_основа)
    требовать(канон(план) == канон(пересчитан), 'план не соответствует независимо выбранному переходу')
    корень = Path(вход['корень'])
    конечные = [{'sha256': з['sha256'], 'режим': з['режим']} for з in план['выходы']]
    старые = [{к: з[к] for к in ('sha256', 'режим')} for з in выбранный_переход['до']]
    def состояния(): return [состояние(корень, з) for з in план['выходы']]
    def результат():
        требовать(состояния() == конечные, 'неполный результат перехода')
        подготовка.коммит.сверить_тексты({'корень': str(корень),
            'запрос': план['выходы'][0]['путь']}, план['команды'])
        события = блоки.прочитать_журнал((корень / план['выходы'][1]['путь']).read_bytes())
        требовать(план['событие'] in события, 'потерян полный агентский literal')
    if состояния() == конечные:
        результат()
        return {'схема': 'fum.результат-происхождения-первого-журнала.1', 'записано': 0}
    требовать(состояния() == старые, 'неизвестный или смешанный исход перехода; повтор запрещён')
    def сверить(номер, временные=()):
        _, привязка, защита, команды, нативное = контур_происхождения(
            вход, выбранное_поручение, выбранная_основа, выбранный_переход, временные=временные)
        требовать(привязка == план['привязка_поручения'] and защита == план['защищённые']
            and канон(команды) == канон(план['команды']), 'контекст перехода изменился')
        требовать(состояния() == конечные[:номер] + старые[номер:], 'пара изменилась до установки')
    записано = 0; попытка_замены = False
    try:
        for номер, выход in enumerate(план['выходы']):
            сверить(номер)
            путь = журнал.точный_путь(корень, выход['путь'], существует=True)
            дескриптор, имя = tempfile.mkstemp(prefix='.происхождение-журнала-', dir=путь.parent)
            временный = Path(имя)
            try:
                данные = base64.b64decode(выход['содержимое'], validate=True)
                требовать(хэш(данные) == выход['sha256'], 'повреждён результат перехода')
                with os.fdopen(дескриптор, 'wb', buffering=0) as поток:
                    записать_полностью(поток, данные)
                    os.fchmod(поток.fileno(), выход['режим']); os.fsync(поток.fileno())
                сверить(номер, (временный.relative_to(корень).as_posix(),))
                попытка_замены = True
                os.replace(временный, путь)
                записано += 1; попытка_замены = False
                каталог = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
                try: os.fsync(каталог)
                finally: os.close(каталог)
            finally:
                if os.path.lexists(временный): временный.unlink()
        результат()
        требовать(контекст(вход, выбранное_поручение, выбранная_основа)[2:] == (
            план['привязка_поручения'], план['защищённые']), 'контекст изменился после перехода')
    except (OSError, ValueError, RuntimeError) as ошибка:
        raise НеполныйПереход(ошибка, записано, попытка_замены or bool(записано)) from ошибка
    return {'схема': 'fum.результат-происхождения-первого-журнала.1', 'записано': 2}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('команда', choices=('план', 'применить', 'происхождение-план', 'происхождение-применить'))
    разбор.add_argument('--вход', required=True)
    разбор.add_argument('--выбранное-поручение', required=True)
    разбор.add_argument('--выбранная-основа', required=True)
    разбор.add_argument('--выбор-sha256', required=True)
    разбор.add_argument('--выбранный-переход')
    разбор.add_argument('--переход-sha256')
    разбор.add_argument('--план')
    разбор.add_argument('--sha256')
    параметры = разбор.parse_args()
    try:
        вход = прочитать_приватный(параметры.вход)
        выбор = прочитать_приватный(параметры.выбранное_поручение)
        основа = прочитать_приватный(параметры.выбранная_основа,
            ожидаемый_sha256=параметры.выбор_sha256)
        установка = параметры.команда.endswith('применить')
        переход = параметры.команда.startswith('происхождение-')
        требовать(установка == bool(параметры.план and параметры.sha256)
            and (установка or параметры.план is None and параметры.sha256 is None),
            'установка требует отдельно выбранные план и SHA')
        требовать(переход == bool(параметры.выбранный_переход and параметры.переход_sha256)
            and (переход or параметры.выбранный_переход is None and параметры.переход_sha256 is None),
            'переход требует отдельный независимый выбор')
        if переход:
            выбор_перехода = прочитать_приватный(параметры.выбранный_переход,
                ожидаемый_sha256=параметры.переход_sha256)
            аргументы = dict(выбранное_поручение=выбор, выбранная_основа=основа,
                выбранный_переход=выбор_перехода)
            результат = (применить_происхождение(вход, прочитать_приватный(параметры.план),
                ожидаемый_sha256=параметры.sha256, **аргументы) if установка
                else подготовить_происхождение(вход, **аргументы))
        else:
            результат = (построить_план(вход, выбранное_поручение=выбор,
            выбранная_основа=основа) if параметры.команда == 'план'
            else применить_план(вход, прочитать_приватный(параметры.план),
                ожидаемый_sha256=параметры.sha256, выбранное_поручение=выбор,
                выбранная_основа=основа))
        print(канон(результат).decode(), end='')
        return 0
    except (OSError, ValueError, TypeError, KeyError, UnicodeError, RuntimeError) as ошибка:
        print(json.dumps({'схема': 'fum.отказ-производственного-состава-журнала.1',
            'автоматический_повтор': False, 'причина': str(ошибка),
            'подтверждённых_замен': ошибка.записано if isinstance(ошибка, НеполныйПереход) else None,
            'возможен_эффект': ошибка.возможен_эффект if isinstance(ошибка, НеполныйПереход) else None},
            ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(главная())

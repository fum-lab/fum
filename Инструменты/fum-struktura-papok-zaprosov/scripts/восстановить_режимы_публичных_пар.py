"""Адресное 0600 → 0644: восемь публичных пар, отдельный план и свидетельства.

Байты, inode и mtime сохраняются. Частичный префикс требует решения ROOT;
автоматического отката и принятия неизвестного результата нет.
"""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import stat
import sys

ПУТЬ_КОДА = 'Инструменты/fum-struktura-papok-zaprosov/scripts/восстановить_режимы_публичных_пар.py'
КОРЕНЬ_КОДА = Path(__file__).resolve().parents[3]
if Path(__file__).absolute() != Path(__file__).resolve():
    raise ValueError('нефизический путь восстановителя')
описание = importlib.util.spec_from_file_location('установщик_для_режимов',
    Path(__file__).with_name('установка_принятого_состава_журнала.py'))
установщик = importlib.util.module_from_spec(описание)
sys.modules[описание.name] = установщик
описание.loader.exec_module(установщик)
контракт, журнал = установщик.контракт, установщик.журнал
ИСХОДНИКИ = (ПУТЬ_КОДА, *установщик.ИСХОДНИКИ)
ЗАГРУЖЕННОЕ = {имя: установщик.прочитать_исходник(имя) for имя in ИСХОДНИКИ}
ОТПЕЧАТКИ = {имя: запись[0] for имя, запись in ЗАГРУЖЕННОЕ.items()}
ПОЛЯ_ВЫБОРА = {'схема', 'координатор', 'корень', 'ветка', 'принятый_коммит',
    'принятое_дерево', 'код', 'каталог_состояния', 'цели'}
ПОЛЯ_ПЛАНА = {'схема', 'выбор', 'выбор_идентичность', 'исходники', 'гит', 'цели'}
требовать = контракт.требовать


def снимок(путь, цель):
    установщик.физический(путь)
    мета = путь.lstat()
    требовать(stat.S_ISREG(мета.st_mode) and мета.st_nlink == 1
        and мета.st_uid == os.getuid(), 'необычная цель, владелец или число ссылок')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        требовать(установщик.идентичность(os.fstat(дескриптор)) == установщик.идентичность(мета), 'подмена при открытии цели')
        with os.fdopen(os.dup(дескриптор), 'rb') as поток:
            сырые = поток.read()
        требовать(контракт.хэш(сырые) == цель['sha256'], 'изменены байты цели')
        требовать(установщик.идентичность(os.fstat(дескриптор)) == установщик.идентичность(мета)
            == установщик.идентичность(путь.lstat()), 'цель изменяется при чтении')
        return list(установщик.идентичность(мета))
    finally:
        os.close(дескриптор)


def контекст(выбор):
    данные = установщик.приватный(выбор)
    контракт.поля(данные, ПОЛЯ_ВЫБОРА)
    требовать(данные['схема'] == 'fum.выбор-восстановления-режимов-пар.1', 'неизвестный выбор')
    контракт.идентичность(данные['координатор'])
    требовать(os.environ.get('CODEX_THREAD_ID') == данные['координатор'], 'выбор другого ROOT')
    каталог = установщик.каталог_состояния(данные['каталог_состояния'])
    корень = журнал.физический_корень(данные['корень'])
    требовать(корень != КОРЕНЬ_КОДА, 'W не исполняет собственный восстановитель')
    требовать(type(данные['ветка']) is str and (данные['ветка'] == 'refs/heads/fuma'
        or данные['ветка'].startswith('refs/heads/codex/')), 'нужна полная ветка fuma либо собственная codex')
    гит = установщик.гит_снимок(корень)
    требовать(гит['коммит'] == данные['принятый_коммит'] and гит['ветка'] == данные['ветка'], 'дрейф H или ref')
    требовать(журнал._гит(корень, 'rev-parse', данные['принятый_коммит'] + '^{tree}').decode().strip()
        == данные['принятое_дерево'], 'подменено принятое дерево')
    контракт.селектор(данные['код'])
    требовать(данные['код']['путь'] == ПУТЬ_КОДА and данные['код']['sha256'] == ОТПЕЧАТКИ[ПУТЬ_КОДА], 'подменён K')
    журнал._гит(корень, 'merge-base', '--is-ancestor', данные['код']['коммит'], данные['принятый_коммит'])
    for имя in ИСХОДНИКИ:
        требовать(установщик.прочитать_исходник(имя) == ЗАГРУЖЕННОЕ[имя]
            and контракт.хэш(журнал._гит(корень, 'show', данные['код']['коммит'] + ':' + имя)) == ОТПЕЧАТКИ[имя],
            'дрейф принятого исполняемого контура')
    дерево = журнал._дерево_коммита(корень, данные['принятый_коммит'])
    требовать(type(данные['цели']) is list and len(данные['цели']) == 8, 'нужны ровно восемь целей')
    имена = []
    for цель in данные['цели']:
        контракт.поля(цель, {'путь', 'blob', 'sha256'})
        контракт.отпечаток(цель['sha256'])
        имя = цель['путь']
        требовать(type(имя) is str, 'неверный путь цели')
        части = Path(имя).parts
        требовать(len(части) == 3 and части[0] == 'Журнал'
            and части[2] in ('запрос.md', 'отчёт.md') and имя == '/'.join(части), 'цель вне публичной пары')
        журнал.точный_путь(корень, имя)
        запись = дерево.get(имя)
        требовать(запись == ('100644', 'blob', цель['blob']), 'непринятая Git-цель или режим')
        требовать(контракт.хэш(журнал._гит(корень, 'cat-file', 'blob', цель['blob'])) == цель['sha256'], 'подменён blob цели')
        индекс = журнал._гит(корень, 'ls-files', '--stage', '-z', '--', имя)
        требовать(индекс == ('100644 ' + цель['blob'] + ' 0\t' + имя).encode() + b'\0', 'дрейф индекса цели')
        имена.append(имя)
    требовать(len(set(имена)) == 8, 'повтор цели')
    установщик.приватный(выбор)
    return корень, каталог, данные, гит


def построить_план(выбор):
    корень, _, данные, гит = контекст(выбор)
    цели = []
    for цель in данные['цели']:
        до = снимок(корень / цель['путь'], цель)
        требовать(stat.S_IMODE(до[2]) == 0o600, 'исходная цель должна иметь ровно 0600')
        цели.append({**цель, 'до': до})
    требовать(контекст(выбор)[3] == гит and all(снимок(корень / ц['путь'], ц) == ц['до'] for ц in цели), 'дрейф при планировании')
    return {'схема': 'fum.план-восстановления-режимов-пар.1', 'выбор': dict(выбор),
        'выбор_идентичность': list(установщик.идентичность(Path(выбор['путь']).lstat())),
        'исходники': ОТПЕЧАТКИ, 'гит': гит, 'цели': цели}


def прочитать_план(план, выбор):
    данные = установщик.приватный(план)
    контракт.поля(данные, ПОЛЯ_ПЛАНА)
    корень, каталог, выбранное, гит = контекст(выбор)
    требовать(данные['схема'] == 'fum.план-восстановления-режимов-пар.1'
        and данные['выбор'] == выбор and данные['выбор_идентичность'] == list(установщик.идентичность(Path(выбор['путь']).lstat()))
        and данные['исходники'] == ОТПЕЧАТКИ and данные['гит'] == гит, 'план, выбор или Git изменён')
    требовать(type(данные['цели']) is list and len(данные['цели']) == 8, 'неверные цели плана')
    for цель, исходная in zip(данные['цели'], выбранное['цели']):
        контракт.поля(цель, {'путь', 'blob', 'sha256', 'до'})
        мета = цель['до']
        требовать({к: цель[к] for к in исходная} == исходная and type(мета) is list and len(мета) == 8
            and all(type(з) is int for з in мета) and мета[2] == (stat.S_IFREG | 0o600)
            and мета[3] == os.getuid() and мета[4] == 1, 'подменена исходная цель плана')
    return корень, каталог, данные


def имя_цели(номер):
    return 'цель-' + str(номер) + '.json'


def тот_же_файл(до, после):
    return после[:2] == до[:2] and после[2] == (stat.S_IFREG | 0o644) and после[3:7] == до[3:7]


def проверить_цели(корень, данные, завершённые):
    for номер, цель in enumerate(данные['цели']):
        ожидаемое = завершённые[номер]['после'] if номер < len(завершённые) else цель['до']
        требовать(снимок(корень / цель['путь'], цель) == ожидаемое, 'поздний дрейф цели ' + str(номер))


def проверить_префикс(каталог, опорные):
    требовать({п.name for п in каталог.iterdir()} == set(опорные), 'чужой служебный префикс')
    for имя, (сырые, мета) in опорные.items():
        требовать(установщик.служебный(каталог / имя)[1] == сырые
            and list(установщик.идентичность((каталог / имя).lstat())) == мета, 'подменено служебное свидетельство')


def применить(план, выбор, *, отказ=None):
    точка = отказ or (lambda _: None)
    with установщик.замок(выбор):
        корень, каталог, данные = прочитать_план(план, выбор)
        требовать(not list(каталог.iterdir()), 'состояние уже содержит префикс; требуется решение ROOT')
        проверить_цели(корень, данные, [])
        опорные = {}
        def опубликовать(имя, запись):
            сырые = установщик.кодировать(запись)
            путь = каталог / имя
            установщик.новое_свидетельство(путь, сырые, точка)
            требовать(установщик.служебный(путь)[1] == сырые, 'неверный readback свидетельства')
            опорные[имя] = (сырые, list(установщик.идентичность(путь.lstat())))
            проверить_префикс(каталог, опорные)
        намерение = {'схема': 'fum.намерение-восстановления-режимов-пар.1', 'план_sha256': план['sha256'],
            'выбор_sha256': выбор['sha256'], 'процесс': os.getpid()}
        опубликовать('намерение.json', намерение)
        точка('после-намерения')
        завершённые = []
        for номер, цель in enumerate(данные['цели']):
            требовать(контекст(выбор)[3] == данные['гит'], 'дрейф перед изменением режима')
            проверить_цели(корень, данные, завершённые)
            проверить_префикс(каталог, опорные)
            путь = корень / цель['путь']
            дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
            try:
                требовать(list(установщик.идентичность(os.fstat(дескриптор))) == цель['до']
                    == list(установщик.идентичность(путь.lstat())), 'подмена перед fchmod')
                os.fchmod(дескриптор, 0o644)
                точка('после-режима-' + str(номер))
                os.fsync(дескриптор)
                после = снимок(путь, цель)
                требовать(тот_же_файл(цель['до'], после)
                    and после == list(установщик.идентичность(os.fstat(дескриптор))), 'дрейф после fchmod')
            finally:
                os.close(дескриптор)
            запись = {'схема': 'fum.цель-восстановления-режимов-пар.1', 'план_sha256': план['sha256'],
                'номер': номер, 'путь': цель['путь'], 'после': после}
            опубликовать(имя_цели(номер), запись)
            завершённые.append(запись)
            точка('после-цели-' + str(номер))
        проверить_цели(корень, данные, завершённые)
        проверить_префикс(каталог, опорные)
        требовать(контекст(выбор)[3] == данные['гит'], 'дрейф перед квитанцией')
        квитанция = {**намерение, 'схема': 'fum.квитанция-восстановления-режимов-пар.1',
            'цели': [контракт.хэш(установщик.кодировать(з)) for з in завершённые]}
        опубликовать('квитанция.json', квитанция)
        точка('после-квитанции')
        проверить_цели(корень, данные, завершённые)
        проверить_префикс(каталог, опорные)
        требовать(контекст(выбор)[3] == данные['гит'], 'дрейф после квитанции')
        проверить_цели(корень, данные, завершённые)
        проверить_префикс(каталог, опорные)
        return {'записей': 8, 'повтор': False, 'процесс': os.getpid(), 'квитанция_sha256': контракт.хэш(установщик.кодировать(квитанция))}


def повтор(план, выбор, завершение):
    корень, каталог, данные = прочитать_план(план, выбор)
    требовать({п.name for п in каталог.iterdir()} == {'намерение.json', 'квитанция.json', *(имя_цели(н) for н in range(8))},
        'неполный либо неизвестный служебный префикс')
    опорные = {п.name: (установщик.служебный(п)[1], list(установщик.идентичность(п.lstat()))) for п in каталог.iterdir()}
    намерение, _ = установщик.служебный(каталог / 'намерение.json')
    контракт.поля(намерение, {'схема', 'план_sha256', 'выбор_sha256', 'процесс'})
    требовать(намерение['схема'] == 'fum.намерение-восстановления-режимов-пар.1'
        and намерение['план_sha256'] == план['sha256'] and намерение['выбор_sha256'] == выбор['sha256']
        and type(намерение['процесс']) is int and намерение['процесс'] > 0, 'подменено намерение')
    квитанция, сырые = установщик.служебный(каталог / 'квитанция.json')
    контракт.поля(квитанция, {*намерение, 'цели'})
    требовать(квитанция == {**намерение, 'схема': 'fum.квитанция-восстановления-режимов-пар.1', 'цели': квитанция['цели']}
        and type(квитанция['цели']) is list and len(квитанция['цели']) == 8, 'подменена квитанция')
    факт = установщик.приватный(завершение)
    мета_завершения = list(установщик.идентичность(Path(завершение['путь']).lstat()))
    контракт.поля(факт, {'схема', 'процесс', 'код_завершения', 'квитанция_sha256'})
    требовать(факт == {'схема': 'fum.завершение-восстановления-режимов-пар.1',
        'процесс': намерение['процесс'], 'код_завершения': 0, 'квитанция_sha256': контракт.хэш(сырые)}
        and type(факт['код_завершения']) is int and намерение['процесс'] != os.getpid(), 'нет независимого завершения 0 другого процесса')
    записи = []
    for номер, цель in enumerate(данные['цели']):
        запись, сырые = установщик.служебный(каталог / имя_цели(номер))
        контракт.поля(запись, {'схема', 'план_sha256', 'номер', 'путь', 'после'})
        требовать(запись['схема'] == 'fum.цель-восстановления-режимов-пар.1' and запись['план_sha256'] == план['sha256']
            and запись['номер'] == номер and запись['путь'] == цель['путь']
            and type(запись['после']) is list and len(запись['после']) == 8
            and all(type(з) is int for з in запись['после']) and тот_же_файл(цель['до'], запись['после'])
            and контракт.хэш(сырые) == квитанция['цели'][номер], 'подменено свидетельство цели')
        записи.append(запись)
    проверить_цели(корень, данные, записи)
    требовать(контекст(выбор)[3] == данные['гит'], 'дрейф при повторе')
    проверить_цели(корень, данные, записи)
    проверить_префикс(каталог, опорные)
    требовать(установщик.приватный(завершение) == факт
        and list(установщик.идентичность(Path(завершение['путь']).lstat())) == мета_завершения,
        'поздняя подмена завершения')
    return {'повтор': True, 'записей': 0, 'процесс': os.getpid()}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выбор', required=True, type=Path, help='JSON selector с полями путь и sha256')
    команды = разбор.add_subparsers(dest='действие', required=True)
    план = команды.add_parser('план')
    план.add_argument('--выход', required=True, type=Path)
    for имя in ('применить', 'повтор'):
        команда = команды.add_parser(имя)
        команда.add_argument('--план', required=True, type=Path, help='JSON selector плана')
        if имя == 'повтор':
            команда.add_argument('--завершение', required=True, type=Path, help='JSON selector факта wait/exit 0')
    параметры = разбор.parse_args()
    выбор = json.loads(параметры.выбор.read_bytes())
    if параметры.действие == 'план':
        сырые = установщик.кодировать(построить_план(выбор))
        выход = установщик.физический(параметры.выход)
        требовать(stat.S_IMODE(выход.parent.stat().st_mode) == 0o700
            and not any(os.path.lexists(п / '.git') for п in выход.parents), 'план должен оставаться вне Git в приватном каталоге')
        with os.fdopen(os.open(выход, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o400), 'wb') as поток:
            поток.write(сырые); поток.flush(); os.fsync(поток.fileno())
        установщик.синхронизировать(выход.parent)
        итог = {'путь': str(выход), 'sha256': контракт.хэш(сырые)}
    else:
        план = json.loads(параметры.план.read_bytes())
        итог = применить(план, выбор) if параметры.действие == 'применить' else повтор(
            план, выбор, json.loads(параметры.завершение.read_bytes()))
    print(json.dumps(итог, ensure_ascii=False, sort_keys=True))


if __name__ == '__main__':
    try:
        главная()
    except (ValueError, OSError) as ошибка:
        print(str(ошибка), file=sys.stderr)
        raise SystemExit(2)

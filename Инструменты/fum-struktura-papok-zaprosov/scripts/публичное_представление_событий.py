"""Чистое адресное представление события и независимый мост точного RAW-повтора."""
import hashlib
import json
from pathlib import Path
import re
import uuid

import отпечатки_загрузки as загрузка

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
КОРЕНЬ = Path(__file__).resolve().parents[3]
ФОРМЫ, SHA_ФОРМ = None, None
ПУТЬ_ФОРМ = 'Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/scripts/path_forms.py'
ПОМЕТКА = 'Публичное представление события (производный текст; версия 1).\nСвязь оригинала: '
СХЕМА = 'fum.публичное-представление-события.1'


def канонические_байты(данные):
    return json.dumps(данные, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def _поля(данные, имена):
    if type(данные) is not dict or set(данные) != set(имена):
        raise ValueError('Неверные поля публичного представления')


def _хэш(значение):
    if type(значение) is not str or re.fullmatch('[0-9a-f]{64}', значение) is None:
        raise ValueError('Нужен точный SHA256')


def _событие(данные):
    _поля(данные, ('идентификатор', 'источник', 'роль', 'текст'))
    _хэш(данные['идентификатор'])
    источник = данные['источник']
    _поля(источник, ('задача', 'начало', 'конец', 'sha256'))
    if type(источник['задача']) is not str or str(uuid.UUID(источник['задача'])) != источник['задача']:
        raise ValueError('Нужен канонический UUID источника')
    _хэш(источник['sha256'])
    if (type(источник['начало']) is not int or type(источник['конец']) is not int
            or not 0 <= источник['начало'] < источник['конец']
            or данные['роль'] not in ('пользователь', 'ассистент', 'наблюдение')
            or type(данные['текст']) is not str or not данные['текст']):
        raise ValueError('Неверное событие или native-диапазон')


def _адреса(текст):
    return {(len(текст[:форма.start].encode()), len(текст[:форма.end].encode()))
            for форма in прочитать_формы().detect_path_forms(текст)}


def прочитать_формы():
    """Загрузить классификатор перед использованием, сохранив точный полный контур."""
    global ФОРМЫ, SHA_ФОРМ
    if Path(загрузка.__file__) != КОРЕНЬ / 'Инструменты/fum-struktura-papok-zaprosov/scripts/отпечатки_загрузки.py':
        raise ValueError('Чужой загрузчик классификатора')
    загрузка.сверить_загрузку(КОРЕНЬ, {
        'Инструменты/fum-struktura-papok-zaprosov/scripts/публичное_представление_событий.py': КОД_ПРИ_ЗАГРУЗКЕ,
        'Инструменты/fum-struktura-papok-zaprosov/scripts/отпечатки_загрузки.py': загрузка.КОД_ПРИ_ЗАГРУЗКЕ})
    if ФОРМЫ is None:
        модуль, SHA = загрузка.загрузить_исходник(КОРЕНЬ / ПУТЬ_ФОРМ, 'формы_адресов_публичного_журнала')
        if Path(модуль.__file__) != КОРЕНЬ / ПУТЬ_ФОРМ or модуль.КОД_ПРИ_ЗАГРУЗКЕ != SHA:
            raise ValueError('Чужой классификатор адресов')
        ФОРМЫ, SHA_ФОРМ = модуль, SHA
    if Path(ФОРМЫ.__file__) != КОРЕНЬ / ПУТЬ_ФОРМ or ФОРМЫ.КОД_ПРИ_ЗАГРУЗКЕ != SHA_ФОРМ:
        raise ValueError('Чужой классификатор адресов')
    загрузка.сверить_загрузку(КОРЕНЬ, {ПУТЬ_ФОРМ: SHA_ФОРМ})
    return ФОРМЫ


def сформировать(оригинал, замены):
    """Изменить только указанные полные адреса в UTF-8-диапазонах; вход не изменяется."""
    _событие(оригинал)
    if оригинал['текст'].startswith(ПОМЕТКА) or type(замены) is not list or not замены:
        raise ValueError('Нужны исходный RAW и конечная непустая карта')
    текст = оригинал['текст'].encode()
    адреса = _адреса(оригинал['текст'])
    if any(type(замена) is not dict or type(замена.get('исходное')) is not str
            or type(замена.get('публичное')) is not str for замена in замены):
        raise ValueError('Карта должна содержать точные строки адресов и представлений')
    if any(исходная['исходное'] in публичная['публичное'] for исходная in замены for публичная in замены):
        raise ValueError('Публичная карта не должна раскрывать выбранные приватные адреса')
    части, публичные, конец_предыдущего = [], [], 0
    for замена in замены:
        _поля(замена, ('начало', 'конец', 'исходное', 'публичное'))
        а, б = замена['начало'], замена['конец']
        if (type(а) is not int or type(б) is not int or not конец_предыдущего <= а < б <= len(текст)
                or (а, б) not in адреса or type(замена['исходное']) is not str
                or текст[а:б] != замена['исходное'].encode()
                or type(замена['публичное']) is not str or not замена['публичное'].strip()
                or '\x00' in замена['публичное'] or _адреса(замена['публичное'])):
            raise ValueError('Карта должна выбирать точные неперекрывающиеся адреса в исходном порядке')
        части += [текст[конец_предыдущего:а], замена['публичное'].encode()]
        публичные.append({'начало': а, 'конец': б, 'sha256': хэш(текст[а:б]), 'публичное': замена['публичное']})
        конец_предыдущего = б
    части.append(текст[конец_предыдущего:])
    связь = {'схема': СХЕМА, 'идентификатор': оригинал['идентификатор'],
        'источник': оригинал['источник'], 'оригинал_sha256': хэш(канонические_байты(оригинал)), 'замены': публичные}
    новое = json.loads(канонические_байты(оригинал))
    новое['текст'] = ПОМЕТКА + канонические_байты(связь).decode() + '\n\n' + b''.join(части).decode()
    return новое


def _уникальные_поля(пары):
    данные = {}
    for ключ, значение in пары:
        if ключ in данные:
            raise ValueError('Повтор JSON-поля')
        данные[ключ] = значение
    return данные


def прочитать_связь(установленное):
    _событие(установленное)
    текст = установленное['текст']
    if not текст.startswith(ПОМЕТКА):
        raise ValueError('Нет явного публичного конверта')
    строка, разделитель, _ = текст[len(ПОМЕТКА):].partition('\n\n')
    if not разделитель:
        raise ValueError('Нет границы публичного конверта')
    связь = json.loads(строка, object_pairs_hook=_уникальные_поля)
    _поля(связь, ('схема', 'идентификатор', 'источник', 'оригинал_sha256', 'замены'))
    if (связь['схема'] != СХЕМА or связь['идентификатор'] != установленное['идентификатор']
            or связь['источник'] != установленное['источник'] or канонические_байты(связь).decode() != строка):
        raise ValueError('Неканоническая или чужая связь оригинала')
    _хэш(связь['оригинал_sha256'])
    if type(связь['замены']) is not list or not связь['замены']:
        raise ValueError('Пустая публичная карта')
    for замена in связь['замены']:
        _поля(замена, ('начало', 'конец', 'sha256', 'публичное'))
        _хэш(замена['sha256'])
    return связь


def проверить_повтор(установленное, оригинал):
    """Проверить весь RAW и независимо построить представление; не переписать журнал."""
    try:
        _событие(оригинал)
        связь = прочитать_связь(установленное)
        if связь['оригинал_sha256'] != хэш(канонические_байты(оригинал)):
            return False
        текст = оригинал['текст'].encode()
        замены = []
        for замена in связь['замены']:
            а, б = замена['начало'], замена['конец']
            if type(а) is not int or type(б) is not int or not 0 <= а < б <= len(текст) or хэш(текст[а:б]) != замена['sha256']:
                return False
            замены.append({'начало': а, 'конец': б, 'исходное': текст[а:б].decode(), 'публичное': замена['публичное']})
        return канонические_байты(сформировать(оригинал, замены)) == канонические_байты(установленное)
    except (ValueError, TypeError, KeyError, UnicodeError, OverflowError):
        return False

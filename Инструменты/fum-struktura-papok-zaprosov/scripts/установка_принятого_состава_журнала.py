ПРЕДЕЛ_ВХОДА = 128 * 1024 * 1024


def кодировать(значение):
    return контракт.канон(значение) + b'\n'


def разобрать(данные):
    return журнал._разобрать_данные(данные)


def идентичность(мета):
    return (мета.st_dev, мета.st_ino, мета.st_mode, мета.st_uid, мета.st_nlink,
        мета.st_size, мета.st_mtime_ns, мета.st_ctime_ns)


def физический(путь):
    путь = Path(путь)
    контракт.требовать(путь.is_absolute() and путь == путь.resolve()
        and not any(п.is_symlink() for п in (путь, *путь.parents)), 'нужен физический путь')
    return путь


def приватный(выбранный):
    контракт.поля(выбранный, {'путь', 'sha256'})
    контракт.отпечаток(выбранный['sha256'])
    путь = физический(выбранный['путь'])
    мета = путь.lstat()
    контракт.требовать(stat.S_ISREG(мета.st_mode) and мета.st_uid == os.getuid()
        and мета.st_nlink == 1 and stat.S_IMODE(мета.st_mode) == 0o400
        and stat.S_IMODE(путь.parent.stat().st_mode) == 0o700
        and not any(os.path.lexists(п / '.git') for п in путь.parents), 'нужен приватный неизменяемый вход 0400/0700')
    контракт.требовать(мета.st_size <= ПРЕДЕЛ_ВХОДА, 'слишком большой вход')
    данные = путь.read_bytes()
    контракт.требовать(контракт.хэш(данные) == выбранный['sha256']
        and идентичность(путь.lstat()) == идентичность(мета), 'вход изменился при чтении')
    return разобрать(данные)


def состояние(путь):
    if not os.path.lexists(путь):
        return {'существует': False, 'байты': None, 'режим': None}
    мета = путь.lstat()
    контракт.требовать(stat.S_ISREG(мета.st_mode) and мета.st_nlink == 1,
        'цель должна быть обычным файлом без ссылок')
    данные = путь.read_bytes()
    контракт.требовать(идентичность(путь.lstat()) == идентичность(мета), 'цель изменяется при чтении')
    return {'существует': True, 'байты': base64.b64encode(данные).decode(),
        'режим': stat.S_IMODE(мета.st_mode)}


def снимок_цели(путь):
    до = list(идентичность(путь.lstat())) if os.path.lexists(путь) else None
    данные = состояние(путь)
    после = list(идентичность(путь.lstat())) if os.path.lexists(путь) else None
    контракт.требовать(до == после, 'подмена идентичности цели при чтении')
    return данные, после


def проверить_состояние(данные):
    контракт.поля(данные, {'существует', 'байты', 'режим'})
    контракт.требовать(type(данные['существует']) is bool, 'неверный признак существования')
    if not данные['существует']:
        контракт.требовать(данные['байты'] is None and данные['режим'] is None, 'неверное отсутствующее before')
        return
    контракт.требовать(данные['режим'] == 0o644 and type(данные['режим']) is int
        and type(данные['байты']) is str, 'неверный режим или байты цели')
    try:
        сырые = base64.b64decode(данные['байты'], validate=True)
    except (ValueError, TypeError) as ошибка:
        raise ValueError('неверные байты цели') from ошибка
    контракт.требовать(base64.b64encode(сырые).decode() == данные['байты'], 'неканонические байты цели')


def гит_снимок(корень):
    собственный = физический(журнал._гит(корень, 'rev-parse', '--absolute-git-dir').decode().strip())
    общий = физический(журнал._гит(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').decode().strip())
    файлы = {'индекс': собственный / 'index', 'конфигурация': общий / 'config',
        'конфигурация_дерева': собственный / 'config.worktree'}
    return {'коммит': журнал._гит(корень, 'rev-parse', 'HEAD').decode().strip(),
        'ветка': журнал._гит(корень, 'symbolic-ref', 'HEAD').decode().strip(),
        'файлы': {имя: None if not os.path.lexists(путь) else контракт.хэш(путь.read_bytes())
            for имя, путь in файлы.items()}}


def проверить_журнал(корень, принятый):
    """Полный W/H без зависимости от ещё не установленной навигации."""
    with журнал.ИндексПутей(корень, контракт.ключ_коллизии) as индекс_путей:
        return _проверить_журнал_проход(корень, принятый, индекс_путей)


def _проверить_журнал_проход(корень, принятый, индекс_путей):
    дерево = журнал._дерево_коммита(корень, принятый)
    живое = журнал._живое_дерево(корень, индекс=индекс_путей)
    принято = {п: з for п, з in дерево.items() if п == 'Журнал' or п.startswith('Журнал/')}
    фактическое = {п: з for п, з in живое.items() if п == 'Журнал' or п.startswith('Журнал/')}
    пустые = {п for п in фактическое if п not in принято and len(Path(п).parts) == 3
        and Path(п).name == 'материалы' and str(Path(п).parent / 'запрос.md') in принято
        and str(Path(п).parent / 'отчёт.md') in принято
        and not any((корень / п).iterdir())}
    контракт.требовать(set(фактическое) == set(принято) | пустые, 'полный живой Журнал отличается от H')
    снимок = []
    имена_файлов = [п for п, (_, тип, _) in принято.items() if тип == 'blob']
    принятые_байты = {}
    for начало in range(0, len(имена_файлов), 32):
        имена = имена_файлов[начало:начало + 32]
        принятые_байты.update(журнал._прочитать_объекты(корень, {п: принято[п][2] for п in имена}))
    for имя in sorted(фактическое):
        контракт.требовать(unicodedata.normalize('NFC', имя) == имя, 'неканонический Unicode Журнала')
        путь = журнал.точный_путь(корень, имя, индекс=индекс_путей)
        мета = путь.lstat()
        тип = 'каталог' if stat.S_ISDIR(мета.st_mode) else 'файл'
        запись = {'путь': имя, 'тип': тип, 'режим': мета.st_mode,
            'владелец': мета.st_uid, 'ссылок': мета.st_nlink, 'байт': мета.st_size,
            'устройство': мета.st_dev, 'узел': мета.st_ino, 'изменение': мета.st_mtime_ns,
            'состояние': мета.st_ctime_ns}
        if тип == 'файл':
            части = Path(имя).parts
            материал = len(части) > 3 and части[0] == 'Журнал' and части[2] == 'материалы'
            режим_гита = принято[имя][0]
            допустимые = ({0o600, 0o644} if материал and режим_гита == '100644'
                else {0o755} if режим_гита == '100755'
                else {0o644} if режим_гита == '100644' else set())
            данные = путь.read_bytes()
            контракт.требовать(мета.st_uid == os.getuid() and мета.st_nlink == 1
                and stat.S_IMODE(мета.st_mode) in допустимые
                and данные == принятые_байты[имя] and идентичность(путь.lstat()) == идентичность(мета), 'исторические байты или режим изменены')
            запись['sha256'] = контракт.хэш(данные)
        снимок.append(запись)
    return контракт.хэш(контракт.канон(снимок))


def контекст(выбор):
    данные = приватный(выбор)
    контракт.поля(данные, ПОЛЯ_ВЫБОРА)
    контракт.требовать(данные['схема'] == 'fum.выбор-установки-состава-журнала.1', 'неизвестный независимый выбор')
    контракт.идентичность(данные['координатор'])
    контракт.требовать(os.environ.get('CODEX_THREAD_ID') == данные['координатор'], 'выбор принадлежит другому ROOT')
    каталог_состояния(данные['каталог_состояния'])
    корень = журнал.физический_корень(данные['корень'])
    контракт.требовать(корень != КОРЕНЬ_КОДА, 'кандидат W не исполняет собственный код')
    контракт.селектор(данные['состав']); контракт.селектор(данные['код'])
    контракт.требовать(данные['код']['путь'] == ПУТЬ_КОДА, 'выбран другой установщик')
    снимок = гит_снимок(корень)
    контракт.требовать(снимок['коммит'] == данные['принятый_коммит'] and снимок['ветка'] == данные['ветка'], 'дрейф A/H или ref')
    дерево = журнал._гит(корень, 'rev-parse', данные['принятый_коммит'] + '^{tree}').decode().strip()
    контракт.требовать(дерево == данные['принятое_дерево'], 'подменено полное принятое дерево A')
    контракт.требовать(данные['код']['коммит'] != данные['принятый_коммит'], 'K принят до H')
    журнал._гит(корень, 'merge-base', '--is-ancestor', данные['код']['коммит'], данные['принятый_коммит'])
    контракт.требовать(данные['состав']['коммит'] != данные['принятый_коммит'], 'состав из собственного проверяемого индекса')
    связность.прочитать_объект_гита(корень, данные['код'])
    for имя, ожидаемый in ЗАГРУЖЕННЫЕ_ИСХОДНИКИ.items():
        текущий = прочитать_исходник(имя)
        контракт.требовать(текущий == ЗАГРУЖЕННОЕ_СОСТОЯНИЕ[имя], 'дрейф физических исходников')
        сырые = журнал._гит(корень, 'show', данные['код']['коммит'] + ':' + имя)
        контракт.требовать(текущий[0] == ожидаемый == контракт.хэш(сырые), 'дрейф принятого исполняемого контура')
    контракт.требовать(данные['код']['sha256'] == ЗАГРУЖЕННЫЕ_ИСХОДНИКИ[ПУТЬ_КОДА], 'подменён основной K')
    сырые = связность.прочитать_объект_гита(корень, данные['состав'])
    состав = журнал._разобрать_данные(сырые)
    контракт.требовать(состав['коммит'] == данные['принятый_коммит'], 'H состава не равен A')
    индекс = журнал.построить_принятый_индекс(корень, состав)
    for имя in ЦЕЛИ:
        журнал.точный_путь(корень, имя)
    return корень, данные, состав, сырые, индекс, снимок, проверить_журнал(корень, состав['коммит'])


def построить_план(выбор, ожидаемые):
    корень, данные, состав, сырые, индекс, гит, история = контекст(выбор)
    контракт.требовать(type(ожидаемые) is list and len(ожидаемые) == 2, 'нужны два exact before')
    цели = []
    for имя, до, после in zip(ЦЕЛИ, ожидаемые, (сырые, индекс['байты'])):
        проверить_состояние(до)
        фактическое, мета = снимок_цели(корень / имя)
        контракт.требовать(фактическое == до, 'неверный exact before')
        итог = {'существует': True, 'байты': base64.b64encode(после).decode(), 'режим': 0o644}
        цели.append({'путь': имя, 'до': до, 'после': итог, 'без_записи': до == итог, 'идентичность_до': мета})
    приватный(выбор)
    контракт.требовать(all(снимок_цели(корень / ц['путь']) == (ц['до'], ц['идентичность_до']) for ц in цели), 'цели изменились при планировании')
    контракт.требовать(гит_снимок(корень) == гит and проверить_журнал(корень, состав['коммит']) == история,
        'дрейф при подготовке плана')
    return {'схема': 'fum.план-установки-состава-журнала.2', 'выбор': dict(выбор),
        'выбор_идентичность': list(идентичность(Path(выбор['путь']).lstat())),
        'каталог_состояния': данные['каталог_состояния'], 'исходники': ЗАГРУЖЕННЫЕ_ИСХОДНИКИ, 'гит': гит, 'журнал_sha256': история, 'цели': цели}


def прочитать_план(план, выбор):
    данные = приватный(план)
    контракт.поля(данные, ПОЛЯ_ПЛАНА)
    контракт.требовать(данные['схема'] == 'fum.план-установки-состава-журнала.2'
        and данные['выбор'] == выбор
        and данные['выбор_идентичность'] == list(идентичность(Path(выбор['путь']).lstat()))
        and данные['исходники'] == ЗАГРУЖЕННЫЕ_ИСХОДНИКИ,
        'план или выбор заменён')
    корень, выбранное, состав, сырые, индекс, гит, история = контекст(выбор)
    контракт.требовать(данные['каталог_состояния'] == выбранное['каталог_состояния'], 'подменён выбранный каталог')
    контракт.требовать(данные['гит'] == гит and данные['журнал_sha256'] == история, 'дрейф полного исторического слоя')
    контракт.требовать(type(данные['цели']) is list and len(данные['цели']) == 2, 'нет двух целей плана')
    for цель, имя, после in zip(данные['цели'], ЦЕЛИ, (сырые, индекс['байты'])):
        контракт.поля(цель, {'путь', 'до', 'после', 'без_записи', 'идентичность_до'})
        проверить_состояние(цель['до']); проверить_состояние(цель['после'])
        мета = цель['идентичность_до']
        контракт.требовать((мета is None and not цель['до']['существует'])
            or цель['до']['существует'] and type(мета) is list and len(мета) == 8
            and all(type(з) is int for з in мета) and stat.S_ISREG(мета[2])
            and stat.S_IMODE(мета[2]) == 0o644 and мета[4] == 1, 'неверная исходная идентичность')
        контракт.требовать(цель['путь'] == имя and цель['после'] == {
            'существует': True, 'байты': base64.b64encode(после).decode(), 'режим': 0o644}
            and type(цель['без_записи']) is bool and цель['без_записи'] == (цель['до'] == цель['после']), 'цели или noop подменены')
    return корень, данные, состав


def путь_свидетельства_цели(каталог, номер):
    return каталог / ('цель-' + str(номер) + '.json')


def путь_временного(корень, план, номер):
    return корень / 'Индексы' / ('.fum-состав-' + план['sha256'] + '-' + str(номер) + '.tmp')


def свидетельство_цели(данные, план, номер, *, незавершённый=True):
    каталог = каталог_состояния(данные['каталог_состояния'])
    путь = путь_свидетельства_цели(каталог, номер)
    запись, сырые = служебный(путь, незавершённый=незавершённый)
    _, намерение = прочитать_намерение(каталог, план, данные['выбор'], незавершённый=незавершённый)
    _, _, история = попытки(каталог, намерение, незавершённый=незавершённый)
    допустимые = {контракт.хэш(намерение), *(контракт.хэш(з) for _, з in история)}
    контракт.поля(запись, {'схема', 'намерение_sha256', 'план_sha256', 'создавшая_попытка_sha256',
        'номер', 'после_sha256', 'идентичность'})
    мета = запись['идентичность']
    контракт.требовать(запись['схема'] == 'fum.идентичность-цели-журнала.1'
        and запись['намерение_sha256'] == контракт.хэш(намерение) and запись['план_sha256'] == план['sha256']
        and запись['создавшая_попытка_sha256'] in допустимые and type(запись['номер']) is int and запись['номер'] == номер
        and запись['после_sha256'] == контракт.хэш(base64.b64decode(данные['цели'][номер]['после']['байты']))
        and type(мета) is list and len(мета) == 7 and all(type(з) is int for з in мета)
        and мета[0] >= 0 and мета[1] > 0 and мета[2] == stat.S_IFREG | 0o644
        and мета[3] == os.getuid() and мета[4] == 1 and мета[5] >= 0,
        'чужое свидетельство идентичности цели')
    return запись, сырые


def префикс(корень, данные, план):
    снимки = [снимок_цели(корень / имя) for имя in ЦЕЛИ]
    текущее = [с for с, _ in снимки]
    допустимые = [[ц['после'] if номер < граница else ц['до'] for номер, ц in enumerate(данные['цели'])]
        for граница in range(3)]
    контракт.требовать(текущее in допустимые, 'чужой или обратный префикс; автоматический откат запрещён')
    for номер, ((текущий, мета), цель) in enumerate(zip(снимки, данные['цели'])):
        if текущий == цель['до']:
            контракт.требовать(мета == цель['идентичность_до'], 'подмена inode исходной либо равной цели')
        else:
            запись, _ = свидетельство_цели(данные, план, номер)
            контракт.требовать(мета[:7] == запись['идентичность'], 'подмена inode установленной цели')
    return текущее


def каталог_состояния(путь):
    путь = физический(путь)
    контракт.требовать(путь.is_dir() and путь.stat().st_uid == os.getuid()
        and stat.S_IMODE(путь.stat().st_mode) == 0o700
        and not any(os.path.lexists(п / '.git') for п in (путь, *путь.parents)), 'нужен готовый приватный каталог 0700')
    return путь


def выбранный_каталог(каталог, выбор):
    каталог = каталог_состояния(каталог)
    контракт.требовать(str(каталог) == приватный(выбор)['каталог_состояния'], 'каталог состояния не выбран ROOT')
    return каталог


def служебный(путь, *, незавершённый=False):
    мета = путь.lstat()
    временный = Path(str(путь) + '.tmp')
    связанные = незавершённый and мета.st_nlink == 2 and os.path.lexists(временный) and (
        временный.lstat().st_dev, временный.lstat().st_ino) == (мета.st_dev, мета.st_ino)
    контракт.требовать(stat.S_ISREG(мета.st_mode) and мета.st_uid == os.getuid()
        and (мета.st_nlink == 1 or связанные) and stat.S_IMODE(мета.st_mode) == 0o600,
        'чужое служебное свидетельство')
    контракт.требовать(not os.path.lexists(временный) or связанные, 'чужой временный префикс свидетельства')
    контракт.требовать(мета.st_size <= ПРЕДЕЛ_ВХОДА, 'слишком большое свидетельство')
    сырые = путь.read_bytes()
    контракт.требовать(идентичность(путь.lstat()) == идентичность(мета), 'свидетельство изменилось при чтении')
    данные = разобрать(сырые)
    контракт.требовать(кодировать(данные) == сырые, 'неканоническое свидетельство')
    return данные, сырые


@contextmanager
def замок(выбор):
    приватный(выбор)
    путь = Path(выбор['путь'])
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        контракт.требовать(идентичность(os.fstat(дескриптор)) == идентичность(путь.lstat()), 'замок подменён')
        try:
            fcntl.flock(дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as ошибка:
            raise ValueError('прежний писатель ещё держит замок') from ошибка
        yield
        контракт.требовать(идентичность(os.fstat(дескриптор)) == идентичность(путь.lstat()), 'замок подменён')
    finally:
        os.close(дескриптор)


def синхронизировать(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def завершить_свидетельство(путь, данные):
    контракт.требовать(служебный(путь, незавершённый=True)[1] == данные, 'подменено сохраняемое свидетельство')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)
    временный = Path(str(путь) + '.tmp')
    if os.path.lexists(временный):
        контракт.требовать((путь.lstat().st_dev, путь.lstat().st_ino) == (
            временный.lstat().st_dev, временный.lstat().st_ino), 'чужой временный файл свидетельства')
        временный.unlink()
    синхронизировать(путь.parent)
    контракт.требовать(служебный(путь)[1] == данные, 'финальный readback свидетельства не совпал')


def новое_свидетельство(путь, данные, точка):
    # Публикация link является CAS отсутствующего имени; неизвестный final не заменяется.
    временный = Path(str(путь) + '.tmp')
    дескриптор = os.open(временный, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'wb') as поток:
        поток.write(данные); поток.flush(); os.fsync(поток.fileno())
    os.link(временный, путь, follow_symlinks=False)
    точка('после-публикации-' + путь.stem)
    завершить_свидетельство(путь, данные)


def прочитать_намерение(каталог, план, выбор, *, незавершённый=False):
    данные, сырые = служебный(каталог / 'намерение.json', незавершённый=незавершённый)
    контракт.поля(данные, {'схема', 'план_sha256', 'выбор_sha256', 'процесс'})
    контракт.требовать(данные['схема'] == 'fum.намерение-установки-состава-журнала.2'
        and данные['план_sha256'] == план['sha256'] and данные['выбор_sha256'] == выбор['sha256']
        and type(данные['процесс']) is int and данные['процесс'] > 0, 'чужое намерение')
    return данные, сырые


def попытки(каталог, намерение, *, незавершённый=False):
    имена = sorted(каталог.glob('восстановление-*.json'))
    предыдущий = контракт.хэш(намерение)
    процесс = разобрать(намерение)['процесс']
    снимок = []
    for номер, путь in enumerate(имена, 1):
        контракт.требовать(путь.name == 'восстановление-' + format(номер, '06d') + '.json', 'разрыв истории восстановителей')
        данные, сырые = служебный(путь, незавершённый=незавершённый)
        контракт.поля(данные, {'схема', 'процесс', 'намерение_sha256', 'предыдущая_sha256', 'остановка'})
        контракт.требовать(данные['схема'] == 'fum.попытка-восстановления-журнала.1'
            and type(данные['процесс']) is int and данные['процесс'] > 0
            and данные['намерение_sha256'] == контракт.хэш(намерение)
            and данные['предыдущая_sha256'] == предыдущий, 'чужая попытка восстановления')
        проверить_остановку(данные['остановка'], процесс, намерение, проверять_pid=False)
        процесс, предыдущий = данные['процесс'], контракт.хэш(сырые)
        снимок.append((путь, сырые))
    разрешённые = {'намерение.json', 'квитанция.json', 'цель-0.json', 'цель-1.json'} | {п.name for п, _ in снимок}
    временные = {имя + '.tmp' for имя in разрешённые if незавершённый and os.path.lexists(каталог / имя)}
    контракт.требовать({п.name for п in каталог.iterdir()} <= разрешённые | временные, 'неизвестный префикс служебного состояния')
    return процесс, предыдущий, снимок


def проверить_остановку(остановка, процесс, намерение, *, проверять_pid=True):
    свидетельство = приватный(остановка)
    контракт.поля(свидетельство, {'схема', 'процесс', 'код_завершения', 'намерение_sha256'})
    контракт.требовать(свидетельство['схема'] == 'fum.остановка-установщика-журнала.1'
        and type(свидетельство['процесс']) is int and свидетельство['процесс'] == процесс
        and type(свидетельство['код_завершения']) is int
        and свидетельство['намерение_sha256'] == контракт.хэш(намерение), 'нет независимого ожидания последнего процесса')
    if проверять_pid:
        try:
            os.kill(процесс, 0)
        except ProcessLookupError:
            pass
        else:
            raise ValueError('прежний процесс ещё существует или PID переиспользован')


def итоговая_квитанция(план, выбор, данные, намерение):
    результаты = []
    for номер, цель in enumerate(данные['цели']):
        мета, хэш_свидетельства = цель['идентичность_до'], None
        if not цель['без_записи']:
            запись, сырые = свидетельство_цели(данные, план, номер)
            мета, хэш_свидетельства = запись['идентичность'], контракт.хэш(сырые)
        результаты.append({'путь': цель['путь'], 'sha256': контракт.хэш(base64.b64decode(цель['после']['байты'])),
            'режим': 0o644, 'без_записи': цель['без_записи'], 'идентичность': мета,
            'свидетельство_sha256': хэш_свидетельства})
    return {'схема': 'fum.квитанция-установки-состава-журнала.2', 'план_sha256': план['sha256'],
        'выбор_sha256': выбор['sha256'], 'намерение_sha256': контракт.хэш(намерение),
        'журнал_sha256': данные['журнал_sha256'], 'результаты': результаты}


def проверить_служебный_префикс(каталог, корень, данные, план, выбор, намерение, подготовка=None):
    путь = каталог / 'квитанция.json'
    if os.path.lexists(путь):
        контракт.требовать(префикс(корень, данные, план) == [ц['после'] for ц in данные['цели']],
            'преждевременная квитанция до установки обеих целей')
        ожидаемая = кодировать(итоговая_квитанция(план, выбор, данные, намерение))
        контракт.требовать(служебный(путь, незавершённый=True)[1] == ожидаемая,
            'чужая либо преждевременная квитанция')
    else:
        контракт.требовать(not os.path.lexists(Path(str(путь) + '.tmp')), 'неизвестный временный префикс квитанции')
    for номер, цель in enumerate(данные['цели']):
        путь = корень / цель['путь']
        временный = путь_временного(корень, план, номер)
        свидетельство = путь_свидетельства_цели(каталог, номер)
        есть_свидетельство = os.path.lexists(свидетельство)
        if цель['без_записи']:
            контракт.требовать(not есть_свидетельство and not os.path.lexists(временный), 'лишнее свидетельство равной цели')
        elif есть_свидетельство:
            запись, _ = свидетельство_цели(данные, план, номер)
            if состояние(путь) == цель['после']:
                контракт.требовать(not os.path.lexists(временный), 'лишняя временная установленная цель')
            else:
                контракт.требовать(os.path.lexists(временный), 'потерян временный inode выбранной цели')
                временное, мета = снимок_цели(временный)
                контракт.требовать(временное == цель['после'] and мета[:7] == запись['идентичность'], 'подмена временной цели')
        elif os.path.lexists(временный):
            временное, мета = снимок_цели(временный)
            контракт.требовать(подготовка == (номер, мета[:7]) and временное == цель['после'],
                'временный inode без долговечного свидетельства')


def повтор(план, выбор, каталог, завершение=None):
    каталог = выбранный_каталог(каталог, выбор)
    контракт.требовать(завершение is not None, 'нужно независимое свидетельство успешного завершения писателя')
    корень, данные, состав = прочитать_план(план, выбор)
    _, намерение = прочитать_намерение(каталог, план, выбор)
    процесс, последняя, попытки_до = попытки(каталог, намерение)
    for номер, цель in enumerate(данные['цели']):
        if not цель['без_записи']:
            свидетельство_цели(данные, план, номер, незавершённый=False)
    проверить_служебный_префикс(каталог, корень, данные, план, выбор, намерение)
    квитанция, сырые = служебный(каталог / 'квитанция.json')
    контракт.требовать(квитанция == итоговая_квитанция(план, выбор, данные, намерение), 'чужая или неполная квитанция')
    окончание = приватный(завершение)
    контракт.поля(окончание, {'схема', 'процесс', 'код_завершения', 'намерение_sha256', 'квитанция_sha256', 'последняя_попытка_sha256'})
    контракт.требовать(окончание == {'схема': 'fum.завершение-установщика-журнала.1',
        'процесс': процесс, 'код_завершения': 0, 'намерение_sha256': контракт.хэш(намерение),
        'квитанция_sha256': контракт.хэш(сырые), 'последняя_попытка_sha256': последняя}
        and type(окончание['процесс']) is int and type(окончание['код_завершения']) is int,
        'нет независимо наблюдённого успешного wait последнего писателя')
    контракт.требовать(префикс(корень, данные, план) == [ц['после'] for ц in данные['цели']], 'результат больше не совпадает с квитанцией')
    журнал.проверить_смешанный(корень, состав)
    прочитать_план(план, выбор)
    проверить_служебный_префикс(каталог, корень, данные, план, выбор, намерение)
    контракт.требовать(прочитать_намерение(каталог, план, выбор)[1] == намерение
        and попытки(каталог, намерение) == (процесс, последняя, попытки_до)
        and служебный(каталог / 'квитанция.json')[1] == сырые and приватный(завершение) == окончание,
        'свидетельства изменились при повторе')
    return {'повтор': True, 'записей': 0, 'квитанция_sha256': контракт.хэш(сырые)}


def применить(план, выбор, каталог, *, отказ=None):
    return установить(план, выбор, каталог, None, отказ)


def восстановить(план, выбор, каталог, остановка, *, отказ=None):
    return установить(план, выбор, каталог, остановка, отказ)


def установить(план, выбор, каталог, остановка, отказ):
    каталог = выбранный_каталог(каталог, выбор)
    корень, данные, состав = прочитать_план(план, выбор)
    префикс(корень, данные, план)
    путь_намерения = каталог / 'намерение.json'
    if os.path.lexists(путь_намерения):
        контракт.требовать(остановка is not None, 'нужны явное восстановление и подтверждённая остановка')
    else:
        контракт.требовать(not any(os.path.lexists(корень / 'Индексы' / ('.fum-состав-' + план['sha256'] + '-' + str(н) + '.tmp')) for н in range(2)), 'временная цель без намерения')
        контракт.требовать(остановка is None and not list(каталог.iterdir())
            and префикс(корень, данные, план) == [ц['до'] for ц in данные['цели']], 'нет первоначального exact before')

    def точка(имя):
        if отказ is not None:
            отказ(имя)

    with замок(выбор):
        прочитать_план(план, выбор)
        if os.path.lexists(путь_намерения):
            _, сырые_намерения = прочитать_намерение(каталог, план, выбор, незавершённый=True)
            процесс, предыдущая, история = попытки(каталог, сырые_намерения, незавершённый=True)
            проверить_служебный_префикс(каталог, корень, данные, план, выбор, сырые_намерения)
            проверить_остановку(остановка, процесс, сырые_намерения)
            завершить_свидетельство(путь_намерения, сырые_намерения)
            for путь, сырые in история:
                завершить_свидетельство(путь, сырые)
            for номер in range(2):
                путь = путь_свидетельства_цели(каталог, номер)
                if os.path.lexists(путь):
                    _, сырые = свидетельство_цели(данные, план, номер)
                    завершить_свидетельство(путь, сырые)
            запись = {'схема': 'fum.попытка-восстановления-журнала.1', 'процесс': os.getpid(),
                'намерение_sha256': контракт.хэш(сырые_намерения), 'предыдущая_sha256': предыдущая, 'остановка': dict(остановка)}
            новое_свидетельство(каталог / ('восстановление-' + format(len(история) + 1, '06d') + '.json'), кодировать(запись), точка)
        else:
            намерение = {'схема': 'fum.намерение-установки-состава-журнала.2',
                'план_sha256': план['sha256'], 'выбор_sha256': выбор['sha256'], 'процесс': os.getpid()}
            сырые_намерения = кодировать(намерение)
            новое_свидетельство(путь_намерения, сырые_намерения, точка)
        процесс, последняя, история = попытки(каталог, сырые_намерения, незавершённый=True)

        def сверить(подготовка=None):
            прочитать_план(план, выбор)
            префикс(корень, данные, план)
            проверить_служебный_префикс(каталог, корень, данные, план, выбор, сырые_намерения, подготовка)
            контракт.требовать(прочитать_намерение(каталог, план, выбор)[1] == сырые_намерения
                and попытки(каталог, сырые_намерения, незавершённый=True) == (процесс, последняя, история), 'намерение или последний писатель изменились')

        точка('после-намерения')
        записей = 0
        for номер, цель in enumerate(данные['цели']):
            сверить()
            путь = корень / цель['путь']
            временный = путь_временного(корень, план, номер)
            после = base64.b64decode(цель['после']['байты'])
            if состояние(путь) != цель['после']:
                if not os.path.lexists(временный):
                    контракт.требовать(not os.path.lexists(путь_свидетельства_цели(каталог, номер)), 'нельзя пересоздать закреплённый inode')
                    дескриптор = os.open(временный, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644)
                    with os.fdopen(дескриптор, 'wb') as поток:
                        os.fchmod(поток.fileno(), 0o644); поток.write(после); поток.flush(); os.fsync(поток.fileno())
                    синхронизировать(временный.parent)
                    _, мета = снимок_цели(временный)
                    стабильная = мета[:7]
                    сверить((номер, стабильная))
                    запись = {'схема': 'fum.идентичность-цели-журнала.1', 'намерение_sha256': контракт.хэш(сырые_намерения),
                        'план_sha256': план['sha256'], 'создавшая_попытка_sha256': последняя, 'номер': номер,
                        'после_sha256': контракт.хэш(после), 'идентичность': стабильная}
                    новое_свидетельство(путь_свидетельства_цели(каталог, номер), кодировать(запись), точка)
                точка('после-временного-' + str(номер))
                сверить()
                запись, _ = свидетельство_цели(данные, план, номер, незавершённый=False)
                временное, мета = снимок_цели(временный)
                контракт.требовать(временное == цель['после'] and мета[:7] == запись['идентичность'], 'временный файл подменён')
                os.replace(временный, путь)
                записей += 1
                точка('после-rename-' + str(номер))
            else:
                контракт.требовать(not os.path.lexists(временный), 'лишний временный файл уже установленной цели')
            сверить()
            контракт.требовать(состояние(путь) == цель['после'], 'readback установленного файла не совпал')
            дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
            try:
                os.fsync(дескриптор)
            finally:
                os.close(дескриптор)
            синхронизировать(путь.parent)
            точка('после-файла-' + str(номер))
        сверить()
        журнал.проверить_смешанный(корень, состав)
        сверить()
        точка('перед-квитанцией')
        сверить()
        сырые_квитанции = кодировать(итоговая_квитанция(план, выбор, данные, сырые_намерения))
        путь_квитанции = каталог / 'квитанция.json'
        if os.path.lexists(путь_квитанции):
            контракт.требовать(остановка is not None, 'квитанция требует восстановления либо независимого повтора')
            завершить_свидетельство(путь_квитанции, сырые_квитанции)
        else:
            новое_свидетельство(путь_квитанции, сырые_квитанции, точка)
        точка('после-квитанции')
        сверить()
        контракт.требовать(служебный(путь_квитанции)[1] == сырые_квитанции, 'поздняя подмена квитанции')
        return {'повтор': False, 'записей': записей, 'квитанция_sha256': контракт.хэш(сырые_квитанции)}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('действие', choices=['план', 'применить', 'восстановить', 'повтор'])
    разбор.add_argument('--выбор', required=True)
    разбор.add_argument('--хэш-выбора', required=True)
    разбор.add_argument('--план', required=True)
    разбор.add_argument('--хэш-плана')
    разбор.add_argument('--ожидаемые')
    разбор.add_argument('--хэш-ожидаемых')
    разбор.add_argument('--каталог-состояния')
    разбор.add_argument('--остановка')
    разбор.add_argument('--хэш-остановки')
    разбор.add_argument('--завершение')
    разбор.add_argument('--хэш-завершения')
    параметры = разбор.parse_args()
    выбор = {'путь': параметры.выбор, 'sha256': параметры.хэш_выбора}
    if параметры.действие == 'план':
        контракт.требовать(параметры.ожидаемые and параметры.хэш_ожидаемых, 'нужен отдельный exact before')
        план = построить_план(выбор, приватный({'путь': параметры.ожидаемые, 'sha256': параметры.хэш_ожидаемых}))
        путь = физический(параметры.план)
        каталог_состояния(путь.parent)
        дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o400)
        with os.fdopen(дескриптор, 'wb') as файл:
            файл.write(кодировать(план)); файл.flush(); os.fsync(файл.fileno())
        синхронизировать(путь.parent)
        return {'план_sha256': контракт.хэш(кодировать(план)), 'разрешение_установки': False}
    контракт.требовать(параметры.хэш_плана and параметры.каталог_состояния, 'нужны выбранный план и состояние')
    план = {'путь': параметры.план, 'sha256': параметры.хэш_плана}
    if параметры.действие == 'восстановить':
        контракт.требовать(параметры.остановка and параметры.хэш_остановки, 'нужно отдельное свидетельство остановки')
        return восстановить(план, выбор, параметры.каталог_состояния,
            {'путь': параметры.остановка, 'sha256': параметры.хэш_остановки})
    if параметры.действие == 'повтор':
        контракт.требовать(параметры.завершение and параметры.хэш_завершения, 'нужно независимо наблюдённое завершение')
        return повтор(план, выбор, параметры.каталог_состояния, {'путь': параметры.завершение, 'sha256': параметры.хэш_завершения})
    return применить(план, выбор, параметры.каталог_состояния)



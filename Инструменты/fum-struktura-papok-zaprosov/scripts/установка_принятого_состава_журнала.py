def сверить_локальные_исходники(данные):
    выбранные = данные['локальные_исходники']
    набор = ДОЧЕРНИЕ_ИСХОДНИКИ if данные['схема'] == СХЕМА_ДОЧЕРНЕГО_ВЫБОРА else ЛОКАЛЬНЫЕ_ИСХОДНИКИ
    контракт.требовать(type(выбранные) is dict and set(выбранные) == set(набор),
        'нужен точный локальный набор тринадцати исходников')
    for значение in выбранные.values(): контракт.отпечаток(значение)
    отпечатки, состояния = исходники_выбора(данные)
    контракт.требовать(выбранные == отпечатки, 'локальные исходники не равны независимому выбору ROOT')
    for имя in набор:
        контракт.требовать(прочитать_исходник(имя) == состояния[имя],
            'дрейф физических локальных исходников')


def приватный(выбранный):
    контракт.поля(выбранный, {'путь', 'sha256'})
    контракт.отпечаток(выбранный['sha256'])
    путь = физический(выбранный['путь'])
    мета = путь.lstat()
    контракт.требовать(stat.S_ISREG(мета.st_mode) and мета.st_uid == os.getuid()
        and мета.st_nlink == 1 and stat.S_IMODE(мета.st_mode) == 0o400
        and stat.S_IMODE(путь.parent.stat().st_mode) == 0o700
        and not any(os.path.lexists(п / '.git') for п in путь.parents), 'нужен приватный неизменяемый вход 0400/0700')
    контракт.требовать(мета.st_size <= ПРЕДЕЛ_ВХОДА, 'слишком большой вход')
    данные = путь.read_bytes()
    контракт.требовать(контракт.хэш(данные) == выбранный['sha256']
        and идентичность(путь.lstat()) == идентичность(мета), 'вход изменился при чтении')
    return разобрать(данные)


def состояние(путь):
    if not os.path.lexists(путь):
        return {'существует': False, 'байты': None, 'режим': None}
    мета = путь.lstat()
    контракт.требовать(stat.S_ISREG(мета.st_mode) and мета.st_nlink == 1,
        'цель должна быть обычным файлом без ссылок')
    данные = путь.read_bytes()
    контракт.требовать(идентичность(путь.lstat()) == идентичность(мета), 'цель изменяется при чтении')
    return {'существует': True, 'байты': base64.b64encode(данные).decode(),
        'режим': stat.S_IMODE(мета.st_mode)}


def снимок_цели(путь):
    до = list(идентичность(путь.lstat())) if os.path.lexists(путь) else None
    данные = состояние(путь)
    после = list(идентичность(путь.lstat())) if os.path.lexists(путь) else None
    контракт.требовать(до == после, 'подмена идентичности цели при чтении')
    return данные, после


def проверить_состояние(данные):
    контракт.поля(данные, {'существует', 'байты', 'режим'})
    контракт.требовать(type(данные['существует']) is bool, 'неверный признак существования')
    if not данные['существует']:
        контракт.требовать(данные['байты'] is None and данные['режим'] is None, 'неверное отсутствующее before')
        return
    контракт.требовать(данные['режим'] == 0o644 and type(данные['режим']) is int
        and type(данные['байты']) is str, 'неверный режим или байты цели')
    try:
        сырые = base64.b64decode(данные['байты'], validate=True)
    except (ValueError, TypeError) as ошибка:
        raise ValueError('неверные байты цели') from ошибка
    контракт.требовать(base64.b64encode(сырые).decode() == данные['байты'], 'неканонические байты цели')


def гит_снимок(корень, *, слияние=False):
    собственный = физический(журнал._гит(корень, 'rev-parse', '--absolute-git-dir').decode().strip())
    общий = физический(журнал._гит(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').decode().strip())
    файлы = {'индекс': собственный / 'index', 'конфигурация': общий / 'config',
        'конфигурация_дерева': собственный / 'config.worktree'}
    снимок = {'коммит': журнал._гит(корень, 'rev-parse', 'HEAD').decode().strip(),
        'ветка': журнал._гит(корень, 'symbolic-ref', 'HEAD').decode().strip(),
        'файлы': {имя: None if not os.path.lexists(путь) else контракт.хэш(путь.read_bytes())
            for имя, путь in файлы.items()}}
    if слияние:
        путь = собственный / 'MERGE_HEAD'
        мета = путь.lstat()
        контракт.требовать(stat.S_ISREG(мета.st_mode) and мета.st_nlink == 1
            and мета.st_uid == os.getuid(), 'необычный MERGE_HEAD')
        сырые = путь.read_bytes()
        контракт.требовать(идентичность(путь.lstat()) == идентичность(мета),
            'MERGE_HEAD меняется при чтении')
        строки = сырые.decode('ascii').splitlines()
        контракт.требовать(len(строки) == 1, 'нужен ровно один родитель слияния')
        снимок['родитель_слияния'] = строки[0]
        снимок['merge_head_sha256'] = контракт.хэш(сырые)
        снимок['merge_head_идентичность'] = list(идентичность(мета))
    return снимок



def _снять_открытую_пару(корень, план, живое, индекс_путей):
    # План связывает происхождение; текущие байты закрепляются отдельно,
    # поскольку наполнитель уже мог изменить первоначальные шаблоны P.1.
    from связность_независимого_журнала import проверить_план
    проверить_план(план)
    контракт.требовать(план['задача'] == план['писатель'] == os.environ.get('CODEX_THREAD_ID'),
        'нужна собственная открытая пара ROOT')
    прочитать_объект_гита(корень, план['основание'])
    префикс = 'Журнал/' + план['журнал']
    имена = sorted(п for п in живое if п == префикс or п.startswith(префикс + '/'))
    контракт.требовать(префикс in имена and all(префикс + '/' + ч in имена
        for ч in ('запрос.md', 'отчёт.md')), 'неполная открытая пара')
    свойства = {к: план[к] for к in ('журнал', 'задача', 'писатель', 'основание', 'этап')}
    файлы, состояния = [], []
    for имя in имена:
        путь = журнал.точный_путь(корень, имя, индекс=индекс_путей)
        мета = путь.lstat()
        каталог = stat.S_ISDIR(мета.st_mode)
        режим = stat.S_IMODE(мета.st_mode)
        контракт.требовать(мета.st_uid == os.getuid() and
            ((каталог and режим in {0o700, 0o755}) or
             (stat.S_ISREG(мета.st_mode) and мета.st_nlink == 1 and режим in {0o600, 0o644, 0o755})),
            'необычный открытый файл, режим или владелец')
        сырые = None if каталог else путь.read_bytes()
        if имя in {'/'.join((префикс, ч)) for ч in ('запрос.md', 'отчёт.md')}:
            контракт.требовать(not каталог and режим == 0o644
                and журнал._свойства(сырые.decode()) == свойства, 'чужая открытая пара или режим')
        контракт.требовать(идентичность(путь.lstat()) == идентичность(мета),
            'открытый слой меняется при чтении')
        запись = {'путь': имя, 'тип': 'каталог' if каталог else 'файл',
            'режим': режим, 'sha256': None if каталог else контракт.хэш(сырые)}
        файлы.append(запись)
        состояния.append({**запись, 'идентичность': list(идентичность(мета))})
    return файлы, контракт.хэш(контракт.канон(состояния))


def снять_открытую_пару(корень, план):
    """Только снимок своей области; выбор и право установки не создаются."""
    корень = журнал.физический_корень(корень)
    with журнал.ИндексПутей(корень, контракт.ключ_коллизии) as индекс:
        файлы, _ = _снять_открытую_пару(корень, план,
            журнал._живое_дерево(корень, индекс=индекс), индекс)
        return {'план': план, 'файлы': файлы}


def проверить_журнал(корень, принятый, *, открытая=None):
    """Полный W/H без зависимости от ещё не установленной навигации."""
    with журнал.ИндексПутей(корень, контракт.ключ_коллизии) as индекс_путей:
        return _проверить_журнал_проход(корень, принятый, индекс_путей, открытая=открытая)


def _проверить_журнал_проход(корень, принятый, индекс_путей, *, открытая=None):
    дерево = (журнал.дерево_состава(корень, принятый) if type(принятый) is dict
        else журнал._дерево_коммита(корень, принятый))
    живое = журнал._живое_дерево(корень, индекс=индекс_путей)
    принято = {п: з for п, з in дерево.items() if п == 'Журнал' or п.startswith('Журнал/')}
    фактическое = {п: з for п, з in живое.items() if п == 'Журнал' or п.startswith('Журнал/')}
    открытый_снимок = None
    if открытая is not None:
        контракт.поля(открытая, {'план', 'файлы'})
        файлы, открытый_снимок = _снять_открытую_пару(
            корень, открытая['план'], живое, индекс_путей)
        имена = {ф['путь'] for ф in файлы}
        контракт.требовать(not имена.intersection(принято),
            'принятый слой нельзя объявить открытой парой')
        контракт.требовать(открытая['файлы'] == файлы,
            'дрейф выбранных файлов открытой пары')
        фактическое = {п: з for п, з in фактическое.items() if п not in имена}
    пустые = {п for п in фактическое if п not in принято and len(Path(п).parts) == 3
        and Path(п).name == 'материалы' and str(Path(п).parent / 'запрос.md') in принято
        and str(Path(п).parent / 'отчёт.md') in принято
        and not any((корень / п).iterdir())}
    контракт.требовать(set(фактическое) == set(принято) | пустые, 'полный живой Журнал отличается от H')
    снимок = []
    # Весь проход и прежде удерживал все принятые байты. Один свежий пакет
    # устраняет запуск процесса на каждые 32 файла; проверка каждого OID
    # остаётся в reader. Между независимыми проходами результат не хранится.
    принятые_байты = журнал._прочитать_объекты(
        корень, {п: з[2] for п, з in принято.items() if з[1] == 'blob'})
    for имя in sorted(фактическое):
        контракт.требовать(unicodedata.normalize('NFC', имя) == имя, 'неканонический Unicode Журнала')
        путь = журнал.точный_путь(корень, имя, индекс=индекс_путей)
        мета = путь.lstat()
        тип = 'каталог' if stat.S_ISDIR(мета.st_mode) else 'файл'
        запись = {'путь': имя, 'тип': тип, 'режим': мета.st_mode,
            'владелец': мета.st_uid, 'ссылок': мета.st_nlink, 'байт': мета.st_size,
            'устройство': мета.st_dev, 'узел': мета.st_ino, 'изменение': мета.st_mtime_ns,
            'состояние': мета.st_ctime_ns}
        if тип == 'файл':
            части = Path(имя).parts
            материал = len(части) > 3 and части[0] == 'Журнал' and части[2] == 'материалы'
            режим_гита = принято[имя][0]
            допустимые = ({0o600, 0o644} if материал and режим_гита == '100644'
                else {0o755} if режим_гита == '100755'
                else {0o644} if режим_гита == '100644' else set())
            данные = путь.read_bytes()
            контракт.требовать(мета.st_uid == os.getuid() and мета.st_nlink == 1
                and stat.S_IMODE(мета.st_mode) in допустимые
                and данные == принятые_байты[имя] and идентичность(путь.lstat()) == идентичность(мета), 'исторические байты или режим изменены')
            запись['sha256'] = контракт.хэш(данные)
        снимок.append(запись)
    if открытая is not None:
        return контракт.хэш(контракт.канон({'история': снимок, 'открытая': открытый_снимок}))
    return контракт.хэш(контракт.канон(снимок))


ПОЛЯ_ВЫБОРА_СЛИЯНИЯ = (ПОЛЯ_ВЫБОРА - {'принятый_коммит', 'принятое_дерево'}) | {
    'источники', 'корень_кода', 'приёмка_кода'}


def проверить_выбор_слияния(данные, корень):
    """ROOT заранее выбирает существующий K; будущий merge не участвует."""
    источники = данные['источники']
    контракт.требовать(type(источники) is list and len(источники) == 2,
        'нужны два источника принятого слияния')
    for источник in источники:
        контракт.поля(источник, {'коммит', 'дерево'})
    коммиты = [и['коммит'] for и in источники]
    журнал.объединение.проверить_коммиты(коммиты, контракт)
    for источник in источники:
        контракт.требовать(журнал._гит(корень, 'cat-file', '-t', источник['коммит']).strip() == b'commit',
            'источник слияния не является коммитом')
        дерево = журнал._гит(корень, 'rev-parse', источник['коммит'] + '^{tree}').decode().strip()
        контракт.требовать(дерево == источник['дерево'], 'подменено принятое дерево источника')
    контракт.требовать(физический(данные['корень_кода']) == КОРЕНЬ_КОДА,
        'подменён физический корень принятого кода')
    к = данные['код']['коммит']
    контракт.требовать(журнал._гит(КОРЕНЬ_КОДА, 'rev-parse', 'HEAD').decode().strip() == к,
        'физический K не соответствует выбранному коммиту')
    контракт.требовать(журнал._гит(корень, 'cat-file', '-t', к).strip() == b'commit',
        'выбранный K не является коммитом')
    контракт.требовать(not журнал._гит(корень, 'rev-list', '--max-count=1', к, '--not', *коммиты).strip(),
        'K не входит в историю ни одного принятого источника')
    контракт.требовать(данные['состав']['коммит'] not in коммиты,
        'носитель состава должен быть отдельным от обоих источников')
    приёмка = приватный(данные['приёмка_кода'])
    контракт.поля(приёмка, {'схема', 'координатор', 'код', 'корень_кода', 'исходники'})
    контракт.требовать(приёмка == {
        'схема': 'fum.ROOT-приёмка-кода-установщика-слияния.1',
        'координатор': данные['координатор'], 'код': данные['код'],
        'корень_кода': данные['корень_кода'], 'исходники': ЗАГРУЖЕННЫЕ_ИСХОДНИКИ},
        'нет закреплённой предварительной ROOT-приёмки K')
    снимок = гит_снимок(корень, слияние=True)
    контракт.требовать(снимок['коммит'] == коммиты[0] and снимок['ветка'] == данные['ветка']
        and снимок['родитель_слияния'] == коммиты[1], 'дрейф источников слияния или ref')
    return снимок, коммиты



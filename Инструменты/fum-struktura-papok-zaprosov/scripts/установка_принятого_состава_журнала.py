def прочитать_исходник(имя):
    путь = КОРЕНЬ_КОДА / имя
    if путь != путь.resolve() or any(п.is_symlink() for п in (путь, *путь.parents)):
        raise ValueError('символическая ссылка в исполняемом контуре')
    мета = путь.lstat()
    if not stat.S_ISREG(мета.st_mode) or мета.st_nlink != 1 or stat.S_IMODE(мета.st_mode) != 0o644:
        raise ValueError('необычный файл или режим исполняемого контура')
    данные = путь.read_bytes()
    if путь.lstat() != мета:
        # Чтение может изменить atime, поэтому сравниваем остальные поля ниже.
        свежая = путь.lstat()
        if (мета.st_dev, мета.st_ino, мета.st_mode, мета.st_nlink, мета.st_size, мета.st_mtime_ns, мета.st_ctime_ns) != (
            свежая.st_dev, свежая.st_ino, свежая.st_mode, свежая.st_nlink, свежая.st_size, свежая.st_mtime_ns, свежая.st_ctime_ns):
            raise ValueError('исполняемый исходник изменяется при чтении')
    return hashlib.sha256(данные).hexdigest(), (мета.st_dev, мета.st_ino, мета.st_mode,
        мета.st_nlink, мета.st_size, мета.st_mtime_ns, мета.st_ctime_ns)



    def test_связность_читает_русский_title_из_новой_пары(сам):
        путь = КОРЕНЬ / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/check-session-coherence.py'
        спецификация = importlib.util.spec_from_file_location('связность_имени_2', путь)
        проверка = importlib.util.module_from_spec(спецификация)
        sys.modules[спецификация.name] = проверка
        спецификация.loader.exec_module(проверка)
        файлы, план = сам.новая_пара()
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный).resolve()
            for файл in файлы:
                цель = корень / файл.path
                цель.parent.mkdir(parents=True, exist_ok=True)
                цель.write_bytes(файл.data)
            запрос = корень / план['файлы'][0]['путь']
            сам.assertIsNotNone(проверка.request_match(запрос))
            сам.assertEqual(проверка.request_title(запрос), 'Создать краткую запись')
            сам.assertEqual(проверка.validate_request_filename_title(запрос), [])
            текст = запрос.read_text()
            запрос.write_text(текст.replace('создать-краткую-запись', 'запись-краткой-сессии'))
            сам.assertTrue(проверка.validate_request_filename_title(запрос))

    def test_преобразователь_получает_очищенную_среду(сам):
        import имя_обычного_журнала as имена
        исходный = subprocess.run
        вызовы = []
        def наблюдать(команда, **параметры):
            if len(команда) == 1 and Path(команда[0]).name == 'preobrazovatj-nazvaniya':
                среда = параметры.get('env')
                сам.assertIsNotNone(среда, 'штатный продукт не должен наследовать среду загрузчика')
                сам.assertFalse(any(к.startswith(('DYLD_', 'LD_')) for к in среда))
                сам.assertEqual(среда.get('LC_ALL'), 'C')
                вызовы.append(1)
            return исходный(команда, **параметры)
        with mock.patch.object(имена.subprocess, 'run', side_effect=наблюдать):
            сам.новая_пара()
        сам.assertEqual(вызовы, [1])


from unittest import mock

КОРЕНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРЕНЬ / 'Инструменты/fum-struktura-papok-zaprosov/scripts'))
import независимый_журнал as журнал

ЭТАЛОН = КОРЕНЬ / 'Журнал/2026-10-25_11-43-39_MSK_поддержать-братиславские-имена-каталогов/материалы/эталон-имён.json'
ОСНОВА = '511404439fb79e8221a8f9c527ebd5aac3a49498'
ПУТЬ_ОСНОВЫ = 'Журнал/2026-10-25_09-37-18_MSK_закрепить-программный-подход-и-ветки-узлов/запрос.md'
ЗАДАЧА = '01a07d3d-d376-7ad2-aafc-67e4c25a67eb'
ПИСАТЕЛЬ = '01a148a5-c088-7373-9665-a3f9b477565e'


class БратиславскоеИмяПары(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        класс.эталон = json.loads(ЭТАЛОН.read_bytes())
        класс.метка = класс.эталон['источники'][0]
        класс.суффикс = класс.эталон['транслитерации'][0].lower()
        сырые = subprocess.run(['git', '-C', str(КОРЕНЬ), 'show', ОСНОВА + ':' + ПУТЬ_ОСНОВЫ],
            check=True, capture_output=True).stdout
        класс.основание = {'коммит': ОСНОВА, 'путь': ПУТЬ_ОСНОВЫ, 'sha256': hashlib.sha256(сырые).hexdigest()}

    def новая_пара(сам, **замены):
        вход = dict(корень=КОРЕНЬ, журнал='2026-10-25_12-00-00_msk_' + сам.суффикс,
            метка=сам.метка, заголовок='Создать краткую запись', задача=ЗАДАЧА,
            команды=['Адресное тестовое поручение корня.'], писатель=ПИСАТЕЛЬ, основание=сам.основание)
        вход.update(замены)
        # RED воспроизводит настоящий отказ прежнего renderer на новом имени.
        функция = getattr(журнал, 'отрендерить_пару_2', журнал.отрендерить_пару)
        return функция(**вход)

    def test_ASCII_каталог_с_русскими_заголовками(сам):
        файлы, план = сам.новая_пара()
        сам.assertTrue(all(ф.path.parts[1].isascii() and ф.path.parts[1] == ф.path.parts[1].lower() for ф in файлы))
        сам.assertTrue(all('2026-10-25 12:00:00 MSK - Создать краткую запись' in ф.data.decode().splitlines()[0] for ф in файлы))
        сам.assertEqual(план['схема'], 'fum.план-обычной-независимой-пары.2')
        сам.assertFalse(план['разрешение_установки'])

    def test_новый_отчёт_выбирает_оба_ASCII_подкаталога(сам):
        файлы, _ = сам.новая_пара()
        каталог = '/'.join(с.lower() for с in сам.эталон['транслитерации'][1:])
        отчёт = next(ф.data.decode() for ф in файлы if ф.path.name == 'отчёт.md')
        сам.assertIn('каталог=' + каталог + ' -->', отчёт)
        сам.assertNotIn('каталог=материалы/запуски-проверок', отчёт)

    def test_неинфинитивный_источник_отклонён(сам):
        with сам.assertRaises((ValueError, журнал.каркас.LayoutError)):
            сам.новая_пара(метка='запись-краткой-сессии', заголовок='Запись краткой сессии')

    def test_ручной_slug_и_чужой_title_отклонены(сам):
        for замены in ({'журнал': '2026-10-25_12-00-00_msk_manual'}, {'заголовок': 'Другое действие'},
            {'журнал': '2026-10-25_12-00-00_MSK_' + сам.суффикс},
            {'журнал': '2026-10-25_12-00-00_msk_' + сам.суффикс.upper()}):
            with сам.subTest(замены=замены), сам.assertRaises((ValueError, журнал.каркас.LayoutError)):
                сам.новая_пара(**замены)

    def test_ресурсы_P1_и_его_байты_не_меняются(сам):
        for имя, ожидаемый in журнал.РЕСУРСЫ.items():
            сам.assertEqual(hashlib.sha256((КОРЕНЬ / имя).read_bytes()).hexdigest(), ожидаемый)
        параметры = (КОРЕНЬ, '2026-10-25_12-00-00_MSK_' + сам.метка, сам.метка,
            'Создать краткую запись', ЗАДАЧА, ['Адресное тестовое поручение корня.'])
        до, план_до = журнал.отрендерить_пару(*параметры, писатель=ПИСАТЕЛЬ, основание=сам.основание)
        сам.новая_пара()
        после, план_после = журнал.отрендерить_пару(*параметры, писатель=ПИСАТЕЛЬ, основание=сам.основание)
        сам.assertEqual(до, после)
        сам.assertEqual(план_до, план_после)

    def test_полный_инвентарь_принимает_только_новые_ASCII_каталоги(сам):
        файлы, план = сам.новая_пара()
        папка = 'Журнал/' + план['журнал']
        каталог = папка + '/' + сам.эталон['транслитерации'][1]
        проверки = каталог + '/' + сам.эталон['транслитерации'][2]
        записи = {'Журнал': ('040000', 'tree', None), 'Журнал/README.md': ('100644', 'blob', None),
            папка: ('040000', 'tree', None), каталог: ('040000', 'tree', None),
            проверки: ('040000', 'tree', None), проверки + '/1.json': ('100644', 'blob', None)}
        записи.update({str(ф.path): ('100644', 'blob', None) for ф in файлы})
        журнал._проверить_структуру(записи)
        for чужое in ('материалы', 'Materialyi', 'materialy\u0456'):
            подмена = {п.replace('/' + сам.эталон['транслитерации'][1], '/' + чужое): з for п, з in записи.items()}
            with сам.subTest(чужое=чужое), сам.assertRaises(ValueError):
                журнал._проверить_структуру(подмена)

    def test_контракт_нового_имени_явный_и_календарный(сам):
        имя = '2026-10-25_12-00-00_msk_' + сам.суффикс
        функция = getattr(журнал.контракт, 'имя_журнала_2', журнал.контракт.имя_журнала)
        сам.assertEqual(функция(имя), '2026-10-25 12:00:00 MSK')
        with сам.assertRaises(ValueError): журнал.контракт.имя_журнала(имя)
        with сам.assertRaises(ValueError): функция(имя.replace('2026-10-25', '2026-02-30'))

    def test_подмена_метаданных_и_Unicode_lookalike_отклонены(сам):
        import имя_обычного_журнала as имена
        файлы, план = сам.новая_пара()
        for ключ, значение in (('ревизия', '0' * 40), ('title', 'Другое действие'),
            ('sourceLabel', 'запись-краткой-сессии'), ('алгоритм', 'ручная-таблица')):
            данные = {**план['имя'], ключ: значение}

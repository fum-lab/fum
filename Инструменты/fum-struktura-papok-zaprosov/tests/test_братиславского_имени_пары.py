    def test_дрейф_исполняемого_посредника_отклонён(сам):
        import имя_обычного_журнала as имена
        сам.новая_пара()
        посредник = КОРЕНЬ / 'Инструменты/fum-bratislavskaya-proyekciya-pamyati/scripts/братиславская_проекция_памяти.py'
        читать = Path.read_bytes
        def изменённый_источник(путь):
            сырые = читать(путь)
            return сырые + b'\n# drift\n' if путь == посредник else сырые
        with mock.patch.object(Path, 'read_bytes', изменённый_источник):
            with сам.assertRaises((ValueError, журнал.каркас.LayoutError)):
                сам.новая_пара()

    def test_метаданные_не_импортируют_чужой_журнал_и_контракт(сам):
        import имя_обычного_журнала as имена
        файлы, план = сам.новая_пара()
        # Снимок mock сохраняет уже установленный собственный checked module;
        # удаление его при восстановлении sys.modules было бы другим отказом.
        исходные = имена.свойства(файлы[0].data.decode(), план['журнал'])
        чужой = types.SimpleNamespace(__file__='/чужой/журнал.py')
        with mock.patch.dict(sys.modules, {'независимый_журнал': чужой,
                'контракт_независимого_журнала': чужой}):
            данные = имена.свойства(файлы[0].data.decode(), план['журнал'])
            сам.assertEqual(исходные, данные)
            сам.assertEqual(план['имя'], данные['имя'])
            сам.assertEqual(план, имена.проверить_план(план))



            план = построить_план(сам, ф); данные = json.loads(Path(план['путь']).read_bytes())
            процесс = ф.работник(план, точка='после-rename-0', корень_кода=str(ф.корень))
            процесс.communicate(timeout=30); сам.assertEqual(73, процесс.returncode)
            сам.assertEqual(данные['цели'][0]['после'], прежние.состояние(ф.корень / ф.модуль.ЦЕЛИ[0]))
            сам.assertEqual(данные['цели'][1]['до'], прежние.состояние(ф.корень / ф.модуль.ЦЕЛИ[1]))
            узел = (ф.корень / ф.модуль.ЦЕЛИ[0]).stat().st_ino
            запрет = ф.работник(план, корень_кода=str(ф.корень))
            запрет.communicate(timeout=30); сам.assertNotEqual(0, запрет.returncode)
            остановка = ф.остановка(процесс, 73)
            восстановитель = ф.работник(план, режим='восстановить', остановка=остановка, корень_кода=str(ф.корень))
            вывод, ошибка = восстановитель.communicate(timeout=30)
            сам.assertEqual(0, восстановитель.returncode, ошибка)
            сам.assertEqual(1, json.loads(вывод)['результат']['записей'])
            сам.assertEqual(узел, (ф.корень / ф.модуль.ЦЕЛИ[0]).stat().st_ino)
            завершение = ф.завершение(восстановитель)
            до, служебное = прежние.наблюдение(ф.корень), прежние.наблюдение(ф.каталог)
            повтор = ф.работник(план, режим='повтор', завершение=завершение, корень_кода=str(ф.корень))
            вывод, ошибка = повтор.communicate(timeout=30)
            сам.assertEqual(0, повтор.returncode, ошибка)
            сам.assertEqual(0, json.loads(вывод)['результат']['записей'])
            сам.assertEqual(до, прежние.наблюдение(ф.корень)); сам.assertEqual(служебное, прежние.наблюдение(ф.каталог))



def хэш(данные): return hashlib.sha256(данные).hexdigest()


@contextlib.contextmanager
def локальная_фикстура():
    ф = прежние.Фикстура(материал_0600=True)
    try:
        ф.старый_селектор = copy.deepcopy(ф.данные_выбора['состав'])
        ф.исторический = ф.материал.parent / 'исторический.raw'
        ф.исторический.write_bytes(b'open-fixture\x00RAW\n'); ф.исторический.chmod(0o600)
        ф.основа.commit()
        ф.принятый = ф.основа.git('rev-parse', 'HEAD').stdout.strip()
        ф.дерево = ф.основа.git('rev-parse', 'HEAD^{tree}').stdout.strip()
        ф.состав = ф.модуль.журнал.состав_принятого_дерева(ф.корень, ф.принятый)
        ф.сырые = прежние.байты(ф.состав)
        ф.основа.git('checkout', '-qb', 'codex/локальный-носитель')
        ф.основа.write('Планирование/принятый-состав.json', ф.сырые); ф.основа.commit()
        ф.источник = ф.основа.git('rev-parse', 'HEAD').stdout.strip()
        ф.основа.git('checkout', '-q', 'codex/фикстура')
        файл = ф.корень / ПЕРЕИСПОЛЬЗОВАНИЕ
        assert not файл.exists(), 'лишний модуль переиспользования в автономной фикстуре'
        for имя in ДОПОЛНИТЕЛЬНЫЕ:
            файл = ф.корень / имя; файл.parent.mkdir(parents=True, exist_ok=True)
            файл.write_bytes((прежние.КОРЕНЬ / имя).read_bytes()); файл.chmod(0o644)
        установщик = ф.корень / прежние.ПУТЬ_УСТАНОВЩИКА
        установщик.write_bytes(установщик.read_bytes() + '\n# Отдельно выбранные локальные байты.\n'.encode())
        ф.данные_выбора = {'схема': СХЕМА, 'координатор': os.environ['CODEX_THREAD_ID'],
            'корень': str(ф.корень), 'ветка': 'refs/heads/codex/фикстура',
            'принятый_коммит': ф.принятый, 'принятое_дерево': ф.дерево,
            'состав': {'коммит': ф.источник, 'путь': 'Планирование/принятый-состав.json', 'sha256': хэш(ф.сырые)},
            'каталог_состояния': str(ф.каталог),
            'локальные_исходники': {и: хэш((ф.корень / и).read_bytes()) for и in ИСХОДНИКИ}}
        ф.выбор = прежние.сохранить(ф.приватный / 'локальный-выбор.json', ф.данные_выбора)
        yield ф
    finally:
        ф.закрыть()


def вариант_выбора(ф, данные):
    номер = len(list(ф.приватный.glob('вариант-*.json')))
    ф.выбор = прежние.сохранить(ф.приватный / f'вариант-{номер}.json', данные)


def планировщик(ф):
    номер = len(list(ф.приватный.glob('ожидаемые-*.json')))
    ожидаемые = прежние.сохранить(ф.приватный / f'ожидаемые-{номер}.json', ф.ожидаемые)
    выход = ф.приватный / f'локальный-план-{номер}.json'
    процесс = subprocess.run([sys.executable, '-B', str(ф.корень / прежние.ПУТЬ_УСТАНОВЩИКА),
        'план', '--выбор', ф.выбор['путь'], '--хэш-выбора', ф.выбор['sha256'],
        '--план', str(выход), '--ожидаемые', ожидаемые['путь'], '--хэш-ожидаемых', ожидаемые['sha256']],
        capture_output=True, text=True, timeout=30, env=os.environ.copy())
    return процесс, выход


def построить_план(сам, ф):
    процесс, путь = планировщик(ф)
    сам.assertEqual(0, процесс.returncode, процесс.stderr)
    ответ = json.loads(процесс.stdout)
    сам.assertIs(False, ответ['разрешение_установки'])
    сам.assertEqual(0o400, stat.S_IMODE(путь.stat().st_mode))
    return {'путь': str(путь), 'sha256': ответ['план_sha256']}



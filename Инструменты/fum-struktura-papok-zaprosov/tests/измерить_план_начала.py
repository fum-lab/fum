"""Открытый профиль подготовки стандартной папки запроса без записи."""
import argparse
import hashlib
import json
import platform
import statistics
import time
from pathlib import Path

from test_план_начала import аргументы, модуль, путь_реализации, репозиторий, снимок


def измерить(действие, повторы=100, серии=5):
    измерения = []
    for _ in range(серии):
        начало = time.perf_counter_ns()
        for _ in range(повторы):
            действие()
        измерения.append(time.perf_counter_ns() - начало)
    return {"повторов_в_серии": повторы, "серий": серии,
            "длительности_серий_наносекунды": измерения,
            "медиана_одного_вызова_наносекунды": statistics.median(измерения) / повторы}


def профиль():
    начало = time.perf_counter_ns()
    with репозиторий() as фикстура:
        подготовка = time.perf_counter_ns() - начало
        до = снимок(фикстура.root)
        измерения = {имя: измерить(lambda: модуль.подготовить_начало(фикстура.root, *аргументы))
                     for имя in ("исходное_измерение", "повтор_без_изменения_алгоритма")}
        файлы, сведения = модуль.подготовить_начало(фикстура.root, *аргументы)
        if снимок(фикстура.root) != до:
            raise RuntimeError("подготовка плана изменила файлы фикстуры")
    корень = Path(__file__).resolve().parents[3]
    файлы_источников = (путь_реализации, Path(__file__),
                        Path(__file__).with_name("test_план_начала.py"),
                        Path(__file__).with_name("test_request_folder_layout.py"),
                        *sorted(модуль.КАТАЛОГ_ШАБЛОНОВ.glob("*.шаблон")))
    return {"схема": "fum.профиль-плана-начала.1", "интерпретатор": platform.python_version(),
            "источники": {путь.relative_to(корень).as_posix(): hashlib.sha256(путь.read_bytes()).hexdigest()
                          for путь in файлы_источников},
            "вход": list(аргументы), "число_соседних_запросов": 2,
            "план": {файл.path.as_posix(): {"режим": файл.mode, "байтов": len(файл.data),
                                          "хэш": hashlib.sha256(файл.data).hexdigest()} for файл in файлы},
            "метаданные": сведения, "подготовка_фикстуры_наносекунды": подготовка,
            "критерий_одного_вызова_наносекунды": 50000000,
            "граница": "Подготовка фикстуры с Git измерена отдельно. Повторные вызовы включают чтение шаблонов, подготовку пяти файлов и не выполняют запись; интервалы последовательны. Повтор измеряет ту же реализацию, ускорение не заявляется.",
            "измерения": измерения}


if __name__ == "__main__":
    параметры = argparse.ArgumentParser(description=__doc__)
    параметры.add_argument("--выход", required=True, type=Path)
    значения = параметры.parse_args()
    результат = профиль()
    значения.выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                             encoding="utf-8")
    print(json.dumps({"измерения": результат["измерения"]}, ensure_ascii=False))

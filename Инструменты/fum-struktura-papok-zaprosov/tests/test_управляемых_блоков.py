"""Смысловые границы полной замены блока и добавления у курсора."""
from pathlib import Path
import hashlib
import importlib
import re
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))


class ПроверкаУправляемыхБлоков(unittest.TestCase):
    def setUp(сам):
        сам.модуль = importlib.import_module('управляемые_блоки')

    def блок(сам, имя, тело):
        return (f'<!-- FUM-КАРТОЧКА:НАЧАЛО {имя} -->\n' + тело
                + f'<!-- FUM-КАРТОЧКА:КОНЕЦ {имя} -->\n').encode()

    def событие(сам, номер=1, текст='Содержательный ответ с ё'):
        return {'идентификатор': hashlib.sha256(str(номер).encode()).hexdigest(),
                'источник': {'задача': '00000000-0000-0000-0000-000000000001',
                             'начало': номер * 100, 'конец': номер * 100 + 50,
                             'sha256': hashlib.sha256(('строка' + str(номер)).encode()).hexdigest()},
                'роль': 'ассистент', 'текст': текст}

    def test_замена_всего_тела_сохраняет_ограждённый_ввод_и_остальные_байты(сам):
        ввод = b'```text\n' + сам.блок('данные', 'Ложный блок\n') + b'```\n'
        исходник = 'До: ё\n'.encode() + ввод + сам.блок('данные', 'Старая строка\nЕщё строка\n') + 'После\n'.encode()
        итог = сам.модуль.заменить_блоки(исходник, {'данные': 'Новый результат\n'.encode()})
        сам.assertEqual(итог, 'До: ё\n'.encode() + ввод + сам.блок('данные', 'Новый результат\n') + 'После\n'.encode())
        сам.assertEqual(сам.модуль.заменить_блоки(итог, {'данные': 'Новый результат\n'.encode()}), итог)

    def test_комментарий_не_превращает_скрытый_маркер_в_управляемый(сам):
        ложный = '<!--\nFUM-КАРТОЧКА:НАЧАЛО данные\nСкрыто\nFUM-КАРТОЧКА:КОНЕЦ данные\n-->\n'.encode()
        исходник = ложный + сам.блок('данные', 'Старое\n')
        итог = сам.модуль.заменить_блоки(исходник, {'данные': 'Новое\n'.encode()})
        сам.assertTrue(итог.startswith(ложный))
        сам.assertEqual(итог[len(ложный):], сам.блок('данные', 'Новое\n'))

    def test_повторные_вложенные_и_неполные_границы_отклоняются(сам):
        правильный = сам.блок('данные', 'Старое\n')
        варианты = [правильный + правильный,
                    '<!-- FUM-КАРТОЧКА:НАЧАЛО данные -->\n'.encode(),
                    '<!-- FUM-КАРТОЧКА:КОНЕЦ данные -->\n'.encode(),
                    сам.блок('данные', сам.блок('другое', 'Вложено\n').decode()),
                    '<!-- FUM-КАРТОЧКА:НАЧАЛО данные --> trailing\n'.encode() + правильный]
        for исходник in варианты:
            with сам.subTest(исходник=исходник), сам.assertRaises(ValueError):
                сам.модуль.заменить_блоки(исходник, {'данные': b'new\n'})

    def test_переводы_строк_и_чужой_блок_сохраняются(сам):
        до = 'До ё\r\n'.encode()
        первый = сам.блок('данные', 'Старое\n').replace(b'\n', b'\r\n')
        чужой = сам.блок('другое', 'Не менять\n').replace(b'\n', b'\r\n')
        итог = сам.модуль.заменить_блоки(до + первый + чужой, {'данные': 'Новое\n'.encode()})
        сам.assertEqual(итог, до + сам.блок('данные', 'Новое\n').replace(b'\n', b'\r\n') + чужой)

    def test_вставка_не_может_подменить_границы(сам):
        with сам.assertRaises(ValueError):
            сам.модуль.заменить_блоки(сам.блок('данные', 'Старое\n'), {'данные': сам.блок('другое', 'Подмена\n')})

    def test_незакрытая_ограда_и_комментарий_не_могут_скрыть_конец(сам):
        for тело in [b'```text\n', b'~~~~\n', b'<!--\n']:
            with сам.subTest(тело=тело), сам.assertRaises(ValueError):
                сам.модуль.заменить_блоки(сам.блок('данные', 'Старое\n'), {'данные': тело})
        for тело in [b'```text\nexample\n```\n', b'<!-- example -->\n']:
            итог = сам.модуль.заменить_блоки(сам.блок('данные', 'Старое\n'), {'данные': тело})
            сам.assertEqual(итог, сам.блок('данные', тело.decode()))

    def test_длинная_ограда_и_тильды_защищают_ложные_маркеры(сам):
        for начало, конец, короткая in [(b'`````text\n', b'`````\n', b'```\n'),
                                          (b'~~~~~\n', b'~~~~~\n', b'~~~\n')]:
            данные = начало + короткая + сам.блок('данные', 'Дословно\n') + конец
            исходник = данные + сам.блок('данные', 'Старое\n')
            итог = сам.модуль.заменить_блоки(исходник, {'данные': 'Новое\n'.encode()})
            сам.assertEqual(итог, данные + сам.блок('данные', 'Новое\n'))

    def test_незакрытая_вставка_не_может_перенести_конец_в_чужую_ограду(сам):
        чужое = '```\n<!-- FUM-КАРТОЧКА:КОНЕЦ данные -->\n```\n```text\nexample\n```\n'.encode()
        исходник = сам.блок('данные', 'Старое\n') + чужое
        with сам.assertRaises(ValueError):
            сам.модуль.заменить_блоки(исходник, {'данные': b'```\n'})

    def test_курсор_сдвигается_вместе_с_одной_новой_записью(сам):
        исходник = 'До журнала\n'.encode() + сам.модуль.пустой_курсор() + 'После журнала\n'.encode()
        итог = сам.модуль.дополнить_журнал(исходник, [сам.событие()])
        сам.assertTrue(итог.startswith('До журнала\n'.encode()))
        сам.assertTrue(итог.endswith('После журнала\n'.encode()))
        сам.assertEqual(сам.модуль.прочитать_журнал(итог), [сам.событие()])
        сам.assertEqual(сам.модуль.дополнить_журнал(итог, [сам.событие()]), итог)

    def test_одинаковый_текст_разных_событий_сохраняется_дважды(сам):
        события = [сам.событие(1), сам.событие(2)]
        итог = сам.модуль.дополнить_журнал(сам.модуль.пустой_курсор(), события)
        сам.assertEqual(сам.модуль.прочитать_журнал(итог), события)
        сам.assertEqual(сам.модуль.дополнить_журнал(итог, события), итог)

    def test_вторая_вставка_сохраняет_старую_запись_и_окружение(сам):
        исходник = b'before\n' + сам.модуль.пустой_курсор() + b'after\n'
        первый = сам.модуль.дополнить_журнал(исходник, [сам.событие(1)])
        курсор = первый.index('<!-- FUM-ЖУРНАЛ:КУРСОР '.encode())
        второй = сам.модуль.дополнить_журнал(первый, [сам.событие(2)])
        сам.assertEqual(второй[:курсор], первый[:курсор])
        сам.assertTrue(второй.endswith(b'after\n'))
        сам.assertEqual(сам.модуль.прочитать_журнал(второй), [сам.событие(1), сам.событие(2)])

    def test_конфликт_источника_роли_и_пакета_отклоняется(сам):
        исходное = сам.событие()
        итог = сам.модуль.дополнить_журнал(сам.модуль.пустой_курсор(), [исходное])
        другая_роль = {**исходное, 'роль': 'пользователь'}
        другой_источник = {**исходное, 'источник': {**исходное['источник'], 'начало': 0}}
        for другое in [другая_роль, другой_источник]:
            for основа in [сам.модуль.пустой_курсор(), итог]:
                with сам.subTest(другое=другое, основа=основа), сам.assertRaises(ValueError):
                    сам.модуль.дополнить_журнал(основа, [исходное, другое])
        сам.assertEqual(сам.модуль.дополнить_журнал(сам.модуль.пустой_курсор(), [исходное, исходное]), итог)

    def test_старый_идентификатор_с_другими_данными_отклоняется(сам):
        итог = сам.модуль.дополнить_журнал(сам.модуль.пустой_курсор(), [сам.событие()])
        with сам.assertRaises(ValueError):
            сам.модуль.дополнить_журнал(итог, [сам.событие(текст='Другой ответ')])

    def test_повреждённая_запись_курсор_и_повторный_курсор_отклоняются(сам):
        итог = сам.модуль.дополнить_журнал(сам.модуль.пустой_курсор(), [сам.событие()])
        for испорчено in [итог.replace('Содержательный'.encode(), 'Изменённый'.encode()),
                          итог + сам.модуль.пустой_курсор(), итог.replace('число=1'.encode(), 'число=2'.encode())]:
            with сам.subTest(испорчено=испорчено), сам.assertRaises(ValueError):
                сам.модуль.прочитать_журнал(испорчено)

    def test_цепочка_не_допускает_перестановку_и_удаление_середины(сам):
        итог = сам.модуль.дополнить_журнал(сам.модуль.пустой_курсор(), [сам.событие(1), сам.событие(2), сам.событие(3)])
        начало = '<!-- FUM-ЖУРНАЛ:ЗАПИСЬ '.encode()
        курсор = '<!-- FUM-ЖУРНАЛ:КУРСОР '.encode()
        позиции = [совпадение.start() for совпадение in re.finditer(re.escape(начало), итог)]
        позиции.append(итог.index(курсор))
        записи = [итог[a:b] for a, b in zip(позиции, позиции[1:])]
        for испорчено in [итог[:позиции[0]] + записи[1] + записи[0] + записи[2] + итог[позиции[-1]:],
                          итог[:позиции[0]] + записи[0] + записи[2] + итог[позиции[-1]:]]:
            with сам.assertRaises(ValueError):
                сам.модуль.прочитать_журнал(испорчено)
        для_порчи = итог[позиции[-1]:]
        хэш_курсора = re.search(rb'sha256=([0-9a-f]{64})', для_порчи).group(1)
        подмена = ('0' if хэш_курсора[:1] != b'0' else '1').encode() + хэш_курсора[1:]
        with сам.assertRaises(ValueError):
            сам.модуль.прочитать_журнал(итог[:позиции[-1]] + для_порчи.replace(хэш_курсора, подмена))

    def test_сырой_текст_с_маркерами_и_длинной_оградой_остаётся_данными(сам):
        событие = сам.событие(текст='```text\n````\n<!-- FUM-ЖУРНАЛ:КУРСОР число=0 -->\nКонец ё\n')
        итог = сам.модуль.дополнить_журнал(сам.модуль.пустой_курсор(), [событие])
        сам.assertEqual(сам.модуль.прочитать_журнал(итог), [событие])


if __name__ == '__main__':
    unittest.main()

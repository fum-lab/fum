"""Три свежих процесса на выбранном полном H; подготовка входов исключена."""
import argparse
import cProfile
import hashlib
import json
import os
from pathlib import Path
import resource
import subprocess
import sys
import time

СЦЕНАРИИ = Path(__file__).resolve().parents[1] / 'scripts'
sys.path.insert(0, str(СЦЕНАРИИ))
import производственный_состав_журнала as производитель


def отпечатки():
    имена = ('производственный_состав_журнала.py', 'независимый_журнал.py')
    результат = {имя: производитель.хэш((СЦЕНАРИИ / имя).read_bytes()) for имя in имена}
    результат['фикстура'] = производитель.хэш(Path(__file__).with_name(
        'test_производственного_состава_журнала.py').read_bytes())
    return результат


def измерить(параметры):
    до = отпечатки()
    if параметры.режим == 'происхождение-фикстуры':
        return измерить_происхождение(до)
    вход = производитель.прочитать_приватный(параметры.вход)
    выбор = производитель.прочитать_приватный(параметры.выбранное_поручение)
    основа = производитель.прочитать_приватный(параметры.выбранная_основа,
        ожидаемый_sha256=параметры.выбор_sha256)
    профиль = cProfile.Profile()
    начало = time.perf_counter_ns(); процесс = time.process_time_ns()
    профиль.enable()
    план = производитель.построить_план(вход, выбранное_поручение=выбор,
        выбранная_основа=основа)
    профиль.disable()
    длительность = time.perf_counter_ns() - начало
    процесс = time.process_time_ns() - процесс
    требуемые = {'контекст', 'память_журнала', 'объект', 'точный_путь',
        '_дерево_коммита', '_прочитать_объекты', '_живое_дерево', 'деревья_пакетом',
        'файл_после_осмотра', 'сверить_предки',
        'состав_принятого_дерева', 'построить_принятый_индекс', 'предыдущее'}
    стадии = []
    for запись in профиль.getstats():
        код = запись.code
        if not isinstance(код, str) and код.co_name in требуемые:
            стадии.append({'имя': код.co_name, 'файл': Path(код.co_filename).name,
                'вызовы': запись.callcount, 'собственное_нс': round(запись.inlinetime * 1e9),
                'вложенное_нс': round(запись.totaltime * 1e9)})
    производитель.требовать(отпечатки() == до, 'код изменился при профилировании')
    return {'схема': 'fum.измерение-производственного-состава-журнала.1',
        'pid': os.getpid(), 'изолированный_интерпретатор': bool(sys.flags.isolated),
        'без_site': bool(sys.flags.no_site), 'без_pyc': bool(sys.dont_write_bytecode),
        'код': до, 'A': вход['основа'], 'H': вход['принятый_журнал'],
        'длительность_нс': длительность, 'процессорное_нс': процесс,
        'максимальный_RSS_байты': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
        'память_записей': len(план['память_журнала']['записи']),
        'память_байтов': sum(з['байты'] for з in план['память_журнала']['записи']),
        'записей_S': len(план['состав']['записи']),
        'выходы': [{'путь': з['путь'], 'sha256': з['sha256'], 'байты': з['байты']}
            for з in план['выходы']],
        'стадии': sorted(стадии, key=lambda з: з['вложенное_нс'], reverse=True)}


def измерить_происхождение(код):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from test_производственного_состава_журнала import ПроверкиПроисхождения
    фикстура = ПроверкиПроисхождения('test_переход_сохраняет_поручение_и_человеческий_ввод_с_LF_и_оградой')
    фикстура.setUp()
    try:
        профиль = cProfile.Profile(); начало = time.perf_counter_ns(); процесс = time.process_time_ns()
        профиль.enable()
        план = фикстура.переход(); первый = фикстура.установить_переход(план)
        до = фикстура.фикс.снимок(); повтор = фикстура.установить_переход(план)
        профиль.disable()
        длительность = time.perf_counter_ns() - начало; процесс = time.process_time_ns() - процесс
        производитель.требовать(первый['записано'] == 2 and повтор['записано'] == 0
            and до == фикстура.фикс.снимок(), 'переход/повтор фикстуры изменил границу')
        стадии = [{'имя': з.code.co_name, 'вызовы': з.callcount,
            'вложенное_нс': round(з.totaltime * 1e9)} for з in профиль.getstats()
            if not isinstance(з.code, str) and з.code.co_name in
            {'контекст', 'контур_происхождения', 'корневые_команды', 'построить_происхождение',
             'подготовить_происхождение', 'применить_происхождение'}]
        производитель.требовать(отпечатки() == код, 'изменён измеряемый код перехода')
        return {'схема': 'fum.измерение-происхождения-журнала.1', 'pid': os.getpid(), 'код': код,
            'изолированный_интерпретатор': bool(sys.flags.isolated),
            'без_site': bool(sys.flags.no_site), 'без_pyc': bool(sys.dont_write_bytecode),
            'фикстура': True, 'первый_эффект': 2, 'повтор_эффектов': 0,
            'длительность_нс': длительность, 'процессорное_нс': процесс,
            'максимальный_RSS_байты': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
            'стадии': sorted(стадии, key=lambda з: з['вложенное_нс'], reverse=True)}
    finally: фикстура.doCleanups()


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--вход', required=True)
    разбор.add_argument('--выбранное-поручение', required=True)
    разбор.add_argument('--выбранная-основа', required=True)
    разбор.add_argument('--выбор-sha256', required=True)
    разбор.add_argument('--выход')
    разбор.add_argument('--измеритель', action='store_true')
    разбор.add_argument('--режим', choices=('полный-H', 'происхождение-фикстуры'), default='полный-H')
    параметры = разбор.parse_args()
    if параметры.измеритель:
        print(json.dumps(измерить(параметры), ensure_ascii=False))
        return
    производитель.требовать(параметры.выход, 'нужен отдельный файл профиля')
    измерения = []
    for _ in range(3):
        команда = [sys.executable, '-I', '-S', '-B', str(Path(__file__).resolve()),
            '--вход', параметры.вход, '--выбранное-поручение', параметры.выбранное_поручение,
            '--выбранная-основа', параметры.выбранная_основа,
            '--выбор-sha256', параметры.выбор_sha256, '--режим', параметры.режим, '--измеритель']
        запуск = subprocess.run(команда, capture_output=True, check=True)
        измерения.append(json.loads(запуск.stdout))
    производитель.требовать(len({з['pid'] for з in измерения}) == 3
        and all(з['pid'] != os.getpid() for з in измерения), 'нужны три разных свежих процесса')
    производитель.требовать(all(з['код'] == измерения[0]['код']
        and (параметры.режим != 'полный-H' or з['выходы'] == измерения[0]['выходы'])
        for з in измерения), 'серия изменила код или S')
    результат = {'схема': 'fum.профиль-производственного-состава-журнала.1',
        'граница': ('Полный producer plan выбранного H; записи в W не выполнялись. '
            if параметры.режим == 'полный-H' else 'Малый переход/повтор на временной Git-фикстуре; '
            'создание фикстуры и импорт исключены. Большой источник ROOT здесь не измерялся. ')
            + 'cProfile включён; вложенные стадии не суммируются. '
            'Кэш ОС не очищался. RSS измерен на macOS в байтах.',
        'режим': параметры.режим, 'измерения': измерения}
    выход = Path(параметры.выход)
    производитель.требовать(not os.path.lexists(выход), 'профиль не перезаписывается')
    with выход.open('xb') as поток: поток.write(производитель.канон(результат))
    print(json.dumps({'процессов': 3, 'длительности_нс': [з['длительность_нс'] for з in измерения],
        'записей_S': измерения[0].get('записей_S')}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

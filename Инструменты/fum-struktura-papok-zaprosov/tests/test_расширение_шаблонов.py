"""Предметные примеры расширения и применения шаблона вопроса."""

import copy
import importlib
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

КОРЕНЬ = Path(__file__).resolve().parents[3]
ОБЛАСТЬ = Path('Инструменты/fum-struktura-papok-zaprosov')
ПРОВЕРЯЕМЫЙ = Path(os.environ.get('FUM_CHECKED_CODE_ROOT', КОРЕНЬ))
sys.path.insert(0, str(ПРОВЕРЯЕМЫЙ / ОБЛАСТЬ / 'scripts'))

ШАБЛОН = '''# {{заголовок}}

{{кратко}}

## Неоднозначность

{{неоднозначность}}

## Вопросы для прояснения

{{вопросы}}

## Источники требований

{{источники}}

## Затронутая документация

{{документация}}
'''
ОПИСАНИЕ = {
    'схема': 'fum.расширение-шаблона.1', 'тип': 'вопрос', 'основание': 'вопрос',
    'версия': 1, 'разделы': [
        {'заголовок': 'Неоднозначность', 'поле': 'неоднозначность'},
        {'заголовок': 'Вопросы для прояснения', 'поле': 'вопросы'},
        {'заголовок': 'Источники требований', 'поле': 'источники'},
        {'заголовок': 'Затронутая документация', 'поле': 'документация'},
    ], 'шаблон': ШАБЛОН,
}
ДАННЫЕ = {'схема': 'fum.документ-шаблона.1', 'тип': 'вопрос',
    'путь': 'Вопросы/граница.md', 'поля': {
        'заголовок': 'Граница', 'кратко': 'Сохраняется ё и {{заголовок}}.',
        'неоднозначность': 'Два требования пока расходятся.',
        'вопросы': '- Где граница?',
        'источники': '- [Исходное требование](../Документация/модель.md)',
        'документация': '- [Модель](../Документация/модель.md)',
    }}
ОЖИДАЕМЫЙ = '''# Граница

Сохраняется ё и {{заголовок}}.

## Неоднозначность

Два требования пока расходятся.

## Вопросы для прояснения

- Где граница?

## Источники требований

- [Исходное требование](../Документация/модель.md)

## Затронутая документация

- [Модель](../Документация/модель.md)
'''


class ПроверкиРасширения(unittest.TestCase):
    def setUp(сам):
        сам.модуль = importlib.import_module('расширение_шаблонов')
        сам.временный = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name)
        for относительный in сам.модуль.ЗАВИСИМОСТИ:
            цель = сам.корень / относительный
            цель.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(ПРОВЕРЯЕМЫЙ / относительный, цель)
        (сам.корень / 'Документация').mkdir()
        (сам.корень / 'Документация/модель.md').write_text(
            '# Модель\n\n[Вопрос](../Вопросы/граница.md)\n', encoding='utf-8')

    def снимок(сам):
        return {str(п.relative_to(сам.корень)): (п.read_bytes(), п.stat().st_mode)
                for п in сам.корень.rglob('*') if п.is_file()}

    def установить(сам):
        план = сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ)
        сам.модуль.применить_план(сам.корень, план)

    def test_точный_план_повтор_и_независимый_документ(сам):
        план = сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ)
        сам.assertEqual(план, сам.модуль.план_расширения(сам.корень, copy.deepcopy(ОПИСАНИЕ)))
        сам.assertEqual(len(план['операции']), 2)
        сам.assertIn('+## Затронутая документация', план['операции'][1]['diff'])
        сам.модуль.применить_план(сам.корень, план)
        снимок = сам.снимок()
        сам.assertTrue(сам.модуль.применить_план(сам.корень, план)['повтор'])
        сам.assertEqual(сам.снимок(), снимок)
        документ = сам.модуль.план_документа(сам.корень, ДАННЫЕ)
        сам.модуль.применить_план(сам.корень, документ)
        сам.assertEqual((сам.корень / ДАННЫЕ['путь']).read_text(), ОЖИДАЕМЫЙ)
        сам.assertTrue(сам.модуль.применить_план(сам.корень, документ)['повтор'])
        сам.assertEqual(len(сам.модуль.план_документа(сам.корень, ДАННЫЕ)['операции']), 0)

    def test_план_переносим_между_деревьями(сам):
        with tempfile.TemporaryDirectory() as каталог:
            другой = Path(каталог) / 'дерево'
            shutil.copytree(сам.корень, другой)
            сам.assertEqual(сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ),
                            сам.модуль.план_расширения(другой, ОПИСАНИЕ))

    def test_устаревание_зависимости_и_режима_без_записи(сам):
        план = сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ)
        (сам.корень / 'AGENTS.md').write_text('Изменённое правило\n')
        снимок = сам.снимок()
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'устарел'):
            сам.модуль.применить_план(сам.корень, план)
        сам.assertEqual(сам.снимок(), снимок)

    def test_несовместимые_шаблоны_не_пишут(сам):
        снимок = сам.снимок()
        for текст in [ШАБЛОН.replace('{{документация}}', ''),
                      ШАБЛОН + '{{кратко}}\n', '<!--\n' + ШАБЛОН + '-->\n',
                      ШАБЛОН.replace('## Затронутая документация', '## Документация'),
                      ШАБЛОН.replace('{{вопросы}}', '{{неизвестное}}')]:
            with сам.subTest(текст=текст):
                вход = {**ОПИСАНИЕ, 'шаблон': текст}
                with сам.assertRaises(сам.модуль.ОшибкаРасширения):
                    сам.модуль.план_расширения(сам.корень, вход)
                сам.assertEqual(сам.снимок(), снимок)

    def test_обязательное_поле_до_рендера(сам):
        сам.установить()
        данные = copy.deepcopy(ДАННЫЕ)
        данные['поля']['документация'] = '  '
        with mock.patch.object(сам.модуль.каркас, '_заполнить_шаблон', side_effect=AssertionError('ранний рендер')):
            with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'поле'):
                сам.модуль.план_документа(сам.корень, данные)

    def test_чужая_проза_и_опасные_пути_не_меняются(сам):
        сам.установить()
        for путь in ['../чужое.md', str(сам.корень / 'чужое.md'), 'Журнал/закрыто/запрос.md', 'Вопросы/README.md']:
            with сам.subTest(путь=путь), сам.assertRaises(сам.модуль.ОшибкаРасширения):
                сам.модуль.план_документа(сам.корень, {**ДАННЫЕ, 'путь': путь})
        (сам.корень / 'Вопросы').mkdir()
        (сам.корень / ДАННЫЕ['путь']).write_text('# Чужая проза\n')
        снимок = сам.снимок()
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'существующ'):
            сам.модуль.план_документа(сам.корень, ДАННЫЕ)
        сам.assertEqual(сам.снимок(), снимок)

    def test_откат_второй_записи(сам):
        план = сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ)
        снимок = сам.снимок()
        исходная = сам.модуль.каркас._install_prepared_file
        вызовы = []
        def установить(корень, файл):
            вызовы.append(файл)
            if len(вызовы) == 2:
                raise OSError('проверочный отказ')
            исходная(корень, файл)
        with mock.patch.object(сам.модуль.каркас, '_install_prepared_file', side_effect=установить):
            with сам.assertRaises(сам.модуль.ОшибкаРасширения):
                сам.модуль.применить_план(сам.корень, план)
        сам.assertEqual(сам.снимок(), снимок)
        сам.assertFalse((сам.корень / ОБЛАСТЬ / 'типы').exists())

    def test_обратные_ссылки_и_структура_проверяются(сам):
        сам.установить()
        (сам.корень / 'Документация/модель.md').write_text('# Модель\n')
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'обратн'):
            сам.модуль.план_документа(сам.корень, ДАННЫЕ)

    def test_изменение_типа_требует_следующей_версии(сам):
        сам.установить()
        новый = copy.deepcopy(ОПИСАНИЕ)
        новый['разделы'].insert(2, {'заголовок': 'Граница ответа', 'поле': 'граница'})
        новый['шаблон'] = ШАБЛОН.replace('## Источники требований', '## Граница ответа\n\n{{граница}}\n\n## Источники требований')
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'верси'):
            сам.модуль.план_расширения(сам.корень, новый)
        новый['версия'] = 2
        план = сам.модуль.план_расширения(сам.корень, новый)
        сам.модуль.применить_план(сам.корень, план)
        сам.assertTrue(сам.модуль.применить_план(сам.корень, план)['повтор'])

    def test_независимый_валидатор_принимает_созданный_вопрос(сам):
        сам.установить()
        план = сам.модуль.план_документа(сам.корень, ДАННЫЕ)
        сам.модуль.применить_план(сам.корень, план)
        (сам.корень / 'Вопросы/README.md').write_text(
            '# Вопросы\n\n## Открытые вопросы\n\n- [Граница](граница.md)\n\n'
            '## Частично прояснённые вопросы\n\nНет.\n')
        результат = subprocess.run([sys.executable, '-B', str(ПРОВЕРЯЕМЫЙ /
            'Инструменты/fum-obratnyiye-ssyilki-voprosov/scripts/check-question-backlinks.py'),
            '--repo-root', str(сам.корень)], capture_output=True, text=True)
        сам.assertEqual(результат.returncode, 0, результат.stderr)

    def test_повреждённый_план_и_изменённые_цели(сам):
        план = сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ)
        план['операции'][0]['путь'] = 'чужая.md'
        снимок = сам.снимок()
        with сам.assertRaises(сам.модуль.ОшибкаРасширения):
            сам.модуль.применить_план(сам.корень, план)
        сам.assertEqual(сам.снимок(), снимок)
        сам.установить()
        план = сам.модуль.план_документа(сам.корень, ДАННЫЕ)
        (сам.корень / 'Документация/модель.md').chmod(0o600)
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'устарел'):
            сам.модуль.применить_план(сам.корень, план)

    def test_символическая_ссылка_и_регистр(сам):
        сам.установить()
        (сам.корень / 'Вопросы').symlink_to(сам.корень / 'Документация', target_is_directory=True)
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'символическ'):
            сам.модуль.план_документа(сам.корень, ДАННЫЕ)
        (сам.корень / 'Вопросы').unlink()
        (сам.корень / 'вопросы').mkdir()
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'регистр'):
            сам.модуль.план_документа(сам.корень, ДАННЫЕ)

    def test_профиль_сохраняет_отказ_и_вложенность(сам):
        наблюдение = сам.модуль.Наблюдение()
        with сам.assertRaises(сам.модуль.ОшибкаРасширения):
            сам.модуль.план_расширения(сам.корень, {}, наблюдение)
        сам.assertEqual([з['исход'] for з in наблюдение.записи], ['отказ', 'отказ'])
        сам.assertEqual(наблюдение.записи[1]['родитель'], 1)
        сам.assertGreaterEqual(наблюдение.записи[0]['длительность_нс'], 0)

    def test_локальный_якорь_не_подменяет_цель(сам):
        сам.установить()
        данные = copy.deepcopy(ДАННЫЕ)
        данные['поля']['документация'] += '\n- [Раздел](#детали)'
        with сам.assertRaises(сам.модуль.ОшибкаРасширения):
            сам.модуль.план_документа(сам.корень, данные)

    def test_повтор_не_принимает_подменённый_предпросмотр(сам):
        план = сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ)
        сам.модуль.применить_план(сам.корень, план)
        план['операции'][0]['diff'] = 'Выдуманный предпросмотр\n'
        план['sha256'] = сам.модуль.хэш(сам.модуль.сериализовать(
            {к: з for к, з in план.items() if к != 'sha256'}).encode())
        with сам.assertRaises(сам.модуль.ОшибкаРасширения):
            сам.модуль.применить_план(сам.корень, план)

    def test_пустой_план_замечает_изменение_режима(сам):
        сам.установить()
        план = сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ)
        сам.assertEqual(план['операции'], [])
        (сам.корень / ОБЛАСТЬ / 'типы/вопрос.json').chmod(0o600)
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'устарел'):
            сам.модуль.применить_план(сам.корень, план)

    def test_чужой_исполняемый_контур_не_выдаётся_за_целевой(сам):
        (сам.корень / ОБЛАСТЬ / 'scripts/request_folder_layout.py').write_text('# Иная реализация\n')
        with сам.assertRaisesRegex(сам.модуль.ОшибкаРасширения, 'исполняем'):
            сам.модуль.план_расширения(сам.корень, ОПИСАНИЕ)

    def test_проверка_каркаса_видит_повреждённое_расширение(сам):
        сам.установить()
        (сам.корень / ОБЛАСТЬ / 'шаблоны/вопрос.md.шаблон').write_text('# Повреждённый шаблон\n')
        with сам.assertRaisesRegex(сам.модуль.каркас.LayoutError, 'шаблон'):
            сам.модуль.каркас.validate_layout(сам.корень)

    def test_ошибка_диагностики_не_меняет_исход_команды(сам):
        вход = сам.корень / 'вход.json'
        вход.write_text(json.dumps(ОПИСАНИЕ, ensure_ascii=False))
        поток = mock.Mock()
        поток.write.side_effect = OSError('диагностический канал недоступен')
        with mock.patch.object(sys, 'stderr', поток), mock.patch.object(sys, 'stdout', io.StringIO()):
            сам.assertEqual(сам.модуль.главная(['план-расширения', '--корень-репозитория',
                str(сам.корень), '--вход', str(вход)]), 0)


if __name__ == '__main__':
    unittest.main()

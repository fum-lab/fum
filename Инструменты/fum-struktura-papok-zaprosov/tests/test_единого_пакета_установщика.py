"""Полный проход читает Git одним свежим пакетом, сохраняя отказы."""
import os
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import unittest
from unittest.mock import patch

from test_установки_принятого_состава_журнала import Фикстура, наблюдение


class ЕдиныйПакетУстановщика(unittest.TestCase):
    def setUp(сам):
        сам.среда = patch.dict(os.environ, {
            'CODEX_THREAD_ID': '00000000-0000-0000-0000-000000000001'})
        сам.среда.start()
        сам.ф = Фикстура(материал_0600=True)
        каталог = сам.ф.материал.parent / 'пакет'
        каталог.mkdir()
        for номер in range(65):
            # Один OID встречается по обе стороны прежней границы 32.
            данные = 'повтор'.encode() if номер in (0, 64) else str(номер).encode()
            (каталог / f'{номер:03d}.bin').write_bytes(данные)
        сам.ф.основа.commit()
        сам.коммит = сам.ф.основа.git('rev-parse', 'HEAD').stdout.strip()
        сам.м = сам.ф.модуль

    def tearDown(сам):
        сам.ф.закрыть()
        сам.среда.stop()

    def проверить(сам):
        return сам.м.проверить_журнал(сам.ф.корень, сам.коммит)

    def test_один_пакет_на_каждый_независимый_полный_проход(сам):
        до = наблюдение(сам.ф.корень)
        исходный = сам.м.журнал._гит
        пакеты = []

        def прочитать(корень, *аргументы, вход=None):
            if аргументы == ('cat-file', '--batch'):
                пакеты.append(вход)
            return исходный(корень, *аргументы, вход=вход)

        with patch.object(сам.м.журнал, '_гит', side_effect=прочитать):
            первый = сам.проверить()
            второй = сам.проверить()
        сам.assertEqual(первый, второй)
        сам.assertEqual(len(пакеты), 2)
        сам.assertEqual(пакеты[0], пакеты[1])
        сам.assertGreater(len(пакеты[0].splitlines()), 32)
        сам.assertEqual(len(пакеты[0].splitlines()), len(set(пакеты[0].splitlines())))
        сам.assertEqual(наблюдение(сам.ф.корень), до)

    def test_ошибки_пакета_сохраняют_отказ_и_исходные_файлы(сам):
        исходный = сам.м.журнал._гит
        до = наблюдение(сам.ф.корень)
        for ошибка in ('oid', 'тип', 'длина', 'данные', 'обрыв', 'хвост'):
            with сам.subTest(ошибка=ошибка):
                def прочитать(корень, *аргументы, вход=None):
                    сырые = исходный(корень, *аргументы, вход=вход)
                    if аргументы != ('cat-file', '--batch'):
                        return сырые
                    заголовок, остаток = сырые.split(b'\n', 1)
                    oid, тип, размер = заголовок.split()
                    if ошибка == 'oid':
                        return b'0' * len(oid) + b' ' + тип + b' ' + размер + b'\n' + остаток
                    if ошибка == 'тип':
                        return oid + b' tree ' + размер + b'\n' + остаток
                    if ошибка == 'длина':
                        return oid + b' blob ' + str(len(сырые) + 1).encode() + b'\n' + остаток
                    if ошибка == 'данные':
                        return заголовок + b'\n' + bytes([остаток[0] ^ 1]) + остаток[1:]
                    if ошибка == 'обрыв':
                        return сырые[:-1]
                    return сырые + 'лишний хвост'.encode()

                with patch.object(сам.м.журнал, '_гит', side_effect=прочитать):
                    with сам.assertRaises(ValueError):
                        сам.проверить()
                сам.assertEqual(наблюдение(сам.ф.корень), до)

    def test_исходное_исключение_не_маскируется(сам):
        исходный = сам.м.журнал._гит
        ошибка = OSError('адресный отказ Git-reader')
        до = наблюдение(сам.ф.корень)

        def прочитать(корень, *аргументы, вход=None):
            if аргументы == ('cat-file', '--batch'):
                raise ошибка
            return исходный(корень, *аргументы, вход=вход)

        with patch.object(сам.м.журнал, '_гит', side_effect=прочитать):
            with сам.assertRaises(OSError) as отказ:
                сам.проверить()
        сам.assertIs(отказ.exception, ошибка)
        сам.assertEqual(наблюдение(сам.ф.корень), до)

    def test_следующий_проход_заново_читает_доступность_объекта(сам):
        сам.проверить()
        oid = сам.ф.основа.git('rev-parse', сам.коммит + ':' +
            (сам.ф.материал.parent / 'пакет/064.bin').relative_to(сам.ф.корень).as_posix()).stdout.strip()
        объект = сам.ф.корень / '.git/objects' / oid[:2] / oid[2:]
        сам.assertTrue(объект.is_file())
        объект.unlink()
        до = наблюдение(сам.ф.корень)
        with сам.assertRaises(ValueError):
            сам.проверить()
        сам.assertEqual(наблюдение(сам.ф.корень), до)

    def test_поздние_живые_байты_не_подменяются_пакетом(сам):
        исходный = сам.м.журнал._прочитать_объекты

        def прочитать(*аргументы, **ключи):
            данные = исходный(*аргументы, **ключи)
            сам.ф.материал.write_bytes('поздняя подмена'.encode())
            return данные

        with patch.object(сам.м.журнал, '_прочитать_объекты', side_effect=прочитать):
            with сам.assertRaises(ValueError):
                сам.проверить()
        сам.assertEqual(сам.ф.материал.read_bytes(), 'поздняя подмена'.encode())

    def test_профиль_отказывает_выходам_до_работников(сам):
        профиль = Path(__file__).with_name('профиль_единого_пакета_установщика.py')
        for вариант in ('существующий', 'Git', 'bare'):
            with сам.subTest(вариант=вариант):
                каталог = сам.ф.приватный / ('выход-' + вариант)
                каталог.mkdir()
                выход = каталог / 'профиль.json'
                if вариант == 'существующий':
                    выход.write_bytes(b'existing')
                elif вариант == 'Git':
                    (каталог / '.git').mkdir()
                else:
                    (каталог / 'HEAD').write_text('ref: refs/heads/test\n')
                    (каталог / 'objects').mkdir()
                до = наблюдение(каталог)
                r = subprocess.run([sys.executable, '-E', '-s', '-S', '-B', str(профиль),
                    '--основа', сам.коммит, '--открытая', str(сам.ф.приватный / 'нечитаемый.json'),
                    '--хэш-открытой', '0' * 64, '--выход', str(выход)],
                    capture_output=True, text=True, timeout=15)
                сам.assertNotEqual(r.returncode, 0)
                сам.assertIn('Нужен новый физический выход вне Git', r.stderr)
                сам.assertEqual(наблюдение(каталог), до)

    def test_профиль_снимает_пару_после_появления_нового_RAW(сам):
        import профиль_единого_пакета_установщика as профиль
        запрос = next((сам.ф.корень / 'Журнал').glob('*/запрос.md'))
        основание = {'коммит': сам.коммит,
            'путь': запрос.relative_to(сам.ф.корень).as_posix(),
            'sha256': hashlib.sha256(запрос.read_bytes()).hexdigest()}
        метка = 'проверить-свежий-снимок'
        имя = '2026-10-22_00-00-00_MSK_' + метка
        файлы, план = сам.м.журнал.подготовить_пару(сам.ф.корень, имя, метка,
            сам.м.журнал.каркас._заголовок_из_метки(метка), os.environ['CODEX_THREAD_ID'],
            ['Проверить поздний RAW'], писатель=os.environ['CODEX_THREAD_ID'], основание=основание)
        сам.м.журнал.установить_пару(сам.ф.корень, файлы, план)
        старый = сам.м.снять_открытую_пару(сам.ф.корень, план)
        материалы = сам.ф.корень / 'Журнал' / имя / 'материалы'
        материалы.mkdir(exist_ok=True)
        (материалы / 'новый-RAW.json').write_text('{}\n')
        путь_плана = сам.ф.приватный / 'план-свежей-пары.json'
        сырые = (json.dumps(план, ensure_ascii=False) + '\n').encode()
        путь_плана.write_bytes(сырые); путь_плана.chmod(0o400)
        п = argparse.Namespace(план_пары=путь_плана,
            хэш_плана_пары=hashlib.sha256(сырые).hexdigest(),
            снимок_открытой=сам.ф.приватный / 'свежая-открытая.json',
            выход=сам.ф.приватный / 'профиль-свежей-пары.json')
        with patch.object(профиль, 'КОРЕНЬ', сам.ф.корень), patch.object(
                профиль, 'загрузить_установщик', return_value=сам.м):
            путь, sha = профиль.подготовить_свежую_пару(п)
        свежая = сам.м.приватный({'путь': str(путь), 'sha256': sha})
        сам.assertNotEqual(старый, свежая)
        with сам.assertRaises(ValueError):
            сам.м.проверить_журнал(сам.ф.корень, сам.коммит, открытая=старый)
        сам.assertIsInstance(сам.м.проверить_журнал(
            сам.ф.корень, сам.коммит, открытая=свежая), str)


if __name__ == '__main__':
    unittest.main()

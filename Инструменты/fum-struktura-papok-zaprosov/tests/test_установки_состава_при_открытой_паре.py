"""Обновление двух индексов сохраняет свою заполненную пару и весь закрытый слой."""
import copy
import hashlib
import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import unittest
from unittest import mock

import test_локальной_установки_принятого_состава as локальный

прежние = локальный.прежние
СХЕМА = 'fum.выбор-локальной-установки-состава-журнала.2'


def открытая_пара(ф):
    имя = '2026-10-21_03-32-11_MSK_проверить-открытый-этап'
    задача = os.environ['CODEX_THREAD_ID']
    основание = ф.данные_выбора['состав']
    файлы, план = ф.модуль.журнал.подготовить_пару(ф.корень, имя,
        имя.split('_MSK_', 1)[1], 'Проверить открытый этап', задача,
        ['Сохранить заполненную пару.\n'], писатель=задача, основание=основание)
    ф.модуль.журнал.установить_пару(ф.корень, файлы, план)
    изменённые = [строка[3:] for строка in ф.основа.git('status', '--porcelain=v1',
        '-z', '--untracked-files=all').stdout.split('\0') if строка]
    разрешение = прежние.сохранить(ф.приватный / 'разрешение-наполнения.json',
        sorted(set(изменённые) | {з['путь'] for з in план['файлы']}))
    вход = {'схема': 'fum.наполнение-карточки.1', 'задача': задача,
        'запрос': план['файлы'][0]['путь'], 'разрешение': разрешение, 'ожидаемые_цели': [],
        'инструменты': [{'имя': 'Python', 'слой': 'CLI', 'версия': None, 'основание': 'Фикстура'}],
        'профиль': {'граница': 'Открытая фикстура', 'стадии': [
            {'имя': 'Наполнение', 'длительность_нс': None, 'основание': 'Без отдельного замера'},
            {'имя': 'Проверка', 'длительность_нс': None, 'основание': 'Без отдельного замера'}]},
        'поля': {'итог': 'Заполненная собственная пара.',
            'проверки': 'Отдельный проверочный процесс.',
            'решения_и_ограничения': 'Проверка установки, не приёмка рабочего ROOT.'}, 'вставки': []}
    файл_входа = прежние.сохранить(ф.приватный / 'наполнение.json', вход)
    файл_плана = ф.приватный / 'план-наполнения.json'
    команда = [sys.executable, '-B', str(прежние.КОРЕНЬ /
        'Инструменты/fum-struktura-papok-zaprosov/scripts/struktura-papok-zaprosov.py')]
    аргументы = ['--repo-root', str(ф.корень), '--вход', файл_входа['путь'], '--план', str(файл_плана)]
    ответ = subprocess.run([*команда, 'наполнение-план', *аргументы], capture_output=True, timeout=30)
    assert ответ.returncode == 0, ответ.stderr.decode()
    ответ = subprocess.run([*команда, 'наполнение-применить', *аргументы,
        '--sha256', json.loads(ответ.stdout)['план_sha256']], capture_output=True, timeout=30)
    assert ответ.returncode == 0, ответ.stderr.decode()
    assert any(локальный.хэш((ф.корень / з['путь']).read_bytes()) != з['sha256'] for з in план['файлы'])
    папка = ф.корень / 'Журнал' / имя
    (папка / 'материалы').mkdir()
    материал = папка / 'материалы/наблюдение.json'
    материал.write_bytes(b'{"observed":true}\n'); материал.chmod(0o600)
    снимок = []
    for путь in sorted([папка, *папка.rglob('*')]):
        мета = путь.lstat()
        снимок.append({'путь': путь.relative_to(ф.корень).as_posix(),
            'тип': 'каталог' if путь.is_dir() else 'файл',
            'режим': stat.S_IMODE(мета.st_mode),
            'sha256': None if путь.is_dir() else локальный.хэш(путь.read_bytes())})
    данные = copy.deepcopy(ф.данные_выбора)
    данные.update(схема=СХЕМА, открытая={'план': план, 'файлы': снимок})
    локальный.вариант_выбора(ф, данные)
    return папка, данные


class ОткрытаяПара(unittest.TestCase):
    def setUp(сам):
        среда = mock.patch.dict(os.environ, {'CODEX_THREAD_ID': '00000000-0000-0000-0000-000000000001'})
        среда.start(); сам.addCleanup(среда.stop)

    def test_установка_и_свежий_повтор_сохраняют_заполненную_пару(сам):
        with локальный.локальная_фикстура() as ф:
            папка, _ = открытая_пара(ф)
            история = прежние.наблюдение(ф.корень / 'Журнал')
            план = локальный.построить_план(сам, ф)
            сам.assertEqual('fum.план-локальной-установки-состава-журнала.2',
                json.loads(Path(план['путь']).read_bytes())['схема'])
            процесс = ф.работник(план, корень_кода=str(ф.корень))
            вывод, ошибка = процесс.communicate(timeout=30)
            сам.assertEqual(0, процесс.returncode, ошибка)
            сам.assertEqual(2, json.loads(вывод)['результат']['записей'])
            сам.assertEqual(история, прежние.наблюдение(ф.корень / 'Журнал'))
            состав = json.loads((ф.корень / 'Индексы/состав-журнала.json').read_bytes())
            сам.assertFalse(any(з['журнал'] == папка.name for з in состав['записи']))
            завершение = ф.завершение(процесс)
            до, служебное = прежние.наблюдение(ф.корень), прежние.наблюдение(ф.каталог)
            повтор = ф.работник(план, режим='повтор', завершение=завершение, корень_кода=str(ф.корень))
            вывод, ошибка = повтор.communicate(timeout=30)
            сам.assertEqual(0, повтор.returncode, ошибка)
            сам.assertEqual(0, json.loads(вывод)['результат']['записей'])
            сам.assertEqual(до, прежние.наблюдение(ф.корень))
            сам.assertEqual(служебное, прежние.наблюдение(ф.каталог))

    def test_чужой_писатель_неполный_снимок_и_старая_схема_отказывают(сам):
        for вид in ('писатель', 'нет-материала', 'старая-схема', 'нет-поля'):
            with сам.subTest(вид=вид), локальный.локальная_фикстура() as ф:
                _, данные = открытая_пара(ф)
                if вид == 'писатель': данные['открытая']['план']['писатель'] = '00000000-0000-0000-0000-000000000002'
                elif вид == 'нет-материала': данные['открытая']['файлы'].pop()
                elif вид == 'старая-схема': данные['схема'] = локальный.СХЕМА
                else: del данные['открытая']
                локальный.вариант_выбора(ф, данные)
                до, служебное = прежние.наблюдение(ф.корень), прежние.наблюдение(ф.каталог)
                процесс, план = локальный.планировщик(ф)
                сам.assertNotEqual(0, процесс.returncode)
                сам.assertFalse(план.exists())
                сам.assertEqual(до, прежние.наблюдение(ф.корень))
                сам.assertEqual(служебное, прежние.наблюдение(ф.каталог))

    def test_поздние_изменения_открытого_и_закрытого_слоя_отказывают_до_эффекта(сам):
        for вид in ('текст', 'материал', 'режим', 'узел', 'каталог', 'история'):
            with сам.subTest(вид=вид), локальный.локальная_фикстура() as ф:
                папка, _ = открытая_пара(ф)
                план = локальный.построить_план(сам, ф)
                файл = папка / 'материалы/наблюдение.json'
                if вид == 'текст': (папка / 'отчёт.md').write_text('подмена\n')
                elif вид == 'материал': файл.write_bytes(b'changed\n')
                elif вид == 'режим': файл.chmod(0o644)
                elif вид == 'узел': прежние.заменить_тот_же_файл(файл)
                elif вид == 'каталог': (папка / 'посторонний').mkdir()
                else: ф.исторический.write_bytes(b'changed history\n')
                до, служебное = прежние.наблюдение(ф.корень), прежние.наблюдение(ф.каталог)
                процесс = ф.работник(план, корень_кода=str(ф.корень))
                _, ошибка = процесс.communicate(timeout=30)
                сам.assertNotEqual(0, процесс.returncode, ошибка)
                сам.assertFalse((ф.каталог / 'намерение.json').exists())
                сам.assertEqual(до, прежние.наблюдение(ф.корень))
                сам.assertEqual(служебное, прежние.наблюдение(ф.каталог))


    def test_дрейф_материала_после_намерения_не_пишет_индексы(сам):
        with локальный.локальная_фикстура() as ф:
            папка, _ = открытая_пара(ф)
            план = локальный.построить_план(сам, ф)
            процесс = ф.работник(план, точка='после-намерения', ждать=True, корень_кода=str(ф.корень))
            сам.assertEqual('готово', прежние.дождаться_точки(процесс, 'после-намерения'))
            (папка / 'материалы/наблюдение.json').write_bytes(b'changed after intent\n')
            до = прежние.наблюдение(ф.корень)
            _, ошибка = процесс.communicate(input='x', timeout=30)
            сам.assertNotEqual(0, процесс.returncode, ошибка)
            сам.assertFalse((ф.каталог / 'квитанция.json').exists())
            сам.assertEqual(до, прежние.наблюдение(ф.корень))

    def test_прерванная_установка_восстанавливается_с_той_же_парой(сам):
        with локальный.локальная_фикстура() as ф:
            папка, _ = открытая_пара(ф)
            история = прежние.наблюдение(ф.корень / 'Журнал')
            план = локальный.построить_план(сам, ф)
            процесс = ф.работник(план, точка='после-rename-0', корень_кода=str(ф.корень))
            процесс.communicate(timeout=30); сам.assertEqual(73, процесс.returncode)
            узел = (ф.корень / ф.модуль.ЦЕЛИ[0]).stat().st_ino
            остановка = ф.остановка(процесс, 73)
            второй = ф.работник(план, режим='восстановить', остановка=остановка, корень_кода=str(ф.корень))
            вывод, ошибка = второй.communicate(timeout=30)
            сам.assertEqual(0, второй.returncode, ошибка)
            сам.assertEqual(1, json.loads(вывод)['результат']['записей'])
            сам.assertEqual(узел, (ф.корень / ф.модуль.ЦЕЛИ[0]).stat().st_ino)
            сам.assertEqual(история, прежние.наблюдение(ф.корень / 'Журнал'))
            завершение = ф.завершение(второй)
            (папка / 'материалы/новый.txt').write_bytes(b'late new material\n')
            до, служебное = прежние.наблюдение(ф.корень), прежние.наблюдение(ф.каталог)
            повтор = ф.работник(план, режим='повтор', завершение=завершение, корень_кода=str(ф.корень))
            _, ошибка = повтор.communicate(timeout=30)
            сам.assertNotEqual(0, повтор.returncode, ошибка)
            сам.assertEqual(до, прежние.наблюдение(ф.корень))
            сам.assertEqual(служебное, прежние.наблюдение(ф.каталог))

    def test_уже_принятая_собственная_пара_не_становится_открытой(сам):
        with локальный.локальная_фикстура() as ф:
            _, данные = открытая_пара(ф)
            ф.основа.commit()
            принятый = ф.основа.git('rev-parse', 'HEAD').stdout.strip()
            дерево = ф.основа.git('rev-parse', 'HEAD^{tree}').stdout.strip()
            состав = ф.модуль.журнал.состав_принятого_дерева(ф.корень, принятый)
            сырые = прежние.байты(состав)
            ф.основа.git('checkout', '-qb', 'codex/состав-с-принятой-парой')
            ф.основа.write('Планирование/новый-состав.json', сырые); ф.основа.commit()
            источник = ф.основа.git('rev-parse', 'HEAD').stdout.strip()
            ф.основа.git('checkout', '-q', 'codex/фикстура')
            данные.update(принятый_коммит=принятый, принятое_дерево=дерево,
                состав={'коммит': источник, 'путь': 'Планирование/новый-состав.json',
                    'sha256': локальный.хэш(сырые)})
            локальный.вариант_выбора(ф, данные)
            до = прежние.наблюдение(ф.корень)
            процесс, план = локальный.планировщик(ф)
            сам.assertNotEqual(0, процесс.returncode)
            сам.assertIn('принятый слой нельзя объявить открытой парой', процесс.stderr)
            сам.assertFalse(план.exists())
            сам.assertEqual(до, прежние.наблюдение(ф.корень))

sys.path.insert(0,sys.argv[1])
м=importlib.import_module(sys.argv[2]);д=json.loads(pathlib.Path(sys.argv[5]).read_bytes())
профиль={}
if д['оборвать']:
    сбой='результат.json' if д['оборвать'] is True else д['оборвать']
    прежнее=м._сохранить
    def отказ(путь,байты):
        if путь.name==сбой:raise OSError('Наблюдаемый отказ сохранения '+сбой)
        return прежнее(путь,байты)

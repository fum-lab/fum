    def test_native_граница_и_точные_начало_конец(сам):
        ф = открытый_этап(сам)
        исходный_отчёт = ф.отчёт.read_bytes()
        сырой = ф.д.нативный.read_bytes()
        for граница in (ф.события[0]['источник']['конец'] - 1, ф.события[2]['источник']['начало'] + 1):
            вход = copy.deepcopy(ф.вход_перехода)
            for выбранное in вход['события']:
                выбранное['native'] = {**выбранное['native'], 'граница': граница, 'sha256': hashlib.sha256(сырой[:граница]).hexdigest()}
            with сам.subTest(граница=граница), сам.assertRaises(ValueError): сам.м.подготовить(ф.корень, вход)
        начало = исходный_отчёт.index(ф.блоки.НАЧАЛО_ЖУРНАЛА)
        _, (_, конец, _) = ф.блоки._прочитать_с_границами(исходный_отчёт)
        for поле, сдвиг in (('начало', 1), ('конец', -1)):
            события = copy.deepcopy(ф.события)
            источник = события[0]['источник']
            источник[поле] += сдвиг
            источник['sha256'] = hashlib.sha256(сырой[источник['начало']:источник['конец']]).hexdigest()
            события[0]['идентификатор'] = hashlib.sha256(ф.блоки.канонические_байты(источник)).hexdigest()
            ф.отчёт.write_bytes(исходный_отчёт[:начало] + ф.блоки.дополнить_журнал(ф.блоки.пустой_курсор(), события) + исходный_отчёт[конец:])
            вход = copy.deepcopy(ф.вход_перехода)
            вход['исходный_отчёт_sha256'] = hashlib.sha256(ф.отчёт.read_bytes()).hexdigest()
            вход['события'][0]['идентификатор'] = события[0]['идентификатор']
            вход['события'][0]['оригинал_sha256'] = hashlib.sha256(ф.блоки.канонические_байты(события[0])).hexdigest()
            with сам.subTest(поле=поле), сам.assertRaises(ValueError): сам.м.подготовить(ф.корень, вход)
        ф.отчёт.write_bytes(исходный_отчёт)
        сам.assertFalse(Path(ф.вход_перехода['архив']).exists())

    def test_настоящий_CLI_и_независимый_SHA(сам):
        ф = открытый_этап(сам)
        вход = ф.сохранить('CLI-вход.json', ф.вход_перехода)
        план = ф.приватный / 'CLI-план.json'
        скрипт = КОРЕНЬ / 'Инструменты/fum-struktura-papok-zaprosov/scripts/переход_публичного_журнала.py'
        def CLI(режим, SHA=None):
            команда = [sys.executable, '-B', str(скрипт), режим, '--корень', str(ф.корень), '--вход', str(вход), '--план', str(план)]
            if SHA is not None: команда += ['--sha256', SHA]
            return subprocess.run(команда, cwd=ф.корень, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
        до = ф.отчёт.read_bytes()
        результат = CLI('план')
        сам.assertEqual(0, результат.returncode, результат.stderr.decode())
        сам.assertEqual('fum.предпросмотр-публичного-журнала.1', json.loads(результат.stdout)['схема'])
        SHA = hashlib.sha256(план.read_bytes()).hexdigest()
        сам.assertEqual(SHA, json.loads(результат.stdout)['план_sha256'])
        отказ = CLI('применить', 'b' * 64)
        сам.assertEqual(2, отказ.returncode)
        сам.assertEqual('fum.отказ-публичного-журнала.1', json.loads(отказ.stderr)['схема'])
        сам.assertFalse(Path(ф.вход_перехода['архив']).exists())
        сам.assertEqual(до, ф.отчёт.read_bytes())
        for режим, схема in [('применить', 'fum.применение-публичного-журнала.1'), ('проверить', 'fum.проверка-публичного-журнала.1')]:
            результат = CLI(режим, SHA)
            сам.assertEqual(0, результат.returncode, результат.stderr.decode())
            сам.assertEqual(схема, json.loads(результат.stdout)['схема'])


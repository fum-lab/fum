def снимок(корень):
    результат = {}
    for путь in корень.rglob('*'):
        сведения = путь.lstat()
        результат[путь.relative_to(корень).as_posix()] = (
            сведения.st_ino, stat.S_IMODE(сведения.st_mode),
            os.readlink(путь) if путь.is_symlink() else путь.read_bytes() if путь.is_file() else None,
        )
    return результат


def занять(путь, вид):
    if вид == 'файл':
        путь.write_bytes(b'preserve old output\x00')
        путь.chmod(0o640)
    elif вид == 'каталог':
        путь.mkdir(mode=0o750)
    else:
        цель = путь.with_name(путь.name + '.цель')
        if вид == 'ссылка':
            цель.write_bytes(b'preserve symlink target\x00')
            цель.chmod(0o640)
        путь.symlink_to(цель.name)



def загрузить_процедуру(путь, ожидаемый):
    if путь.is_symlink() or ПРОФИЛЬ.хэш(путь.read_bytes()) != ожидаемый:
        raise RuntimeError('изменились закреплённые байты процедуры')
    описание = importlib.util.spec_from_file_location('замороженная_' + ожидаемый, путь)
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    return модуль


def этап(вызов):
    начало = time.perf_counter_ns()
    значение = вызов()
    return значение, time.perf_counter_ns() - начало


def проверить_вход(план):
    for запись in план['процедуры'].values():
        if ПРОФИЛЬ.хэш(Path(запись['путь']).read_bytes()) != запись['sha256']:
            raise RuntimeError('изменились байты A/B процедуры')
    if ПРОФИЛЬ.хэш(Path(__file__).read_bytes()) != план['драйвер']['sha256']:
        raise RuntimeError('изменились байты драйвера')
    общий = план['общий']
    for версия in общий['версии'].values():
        if ПРОФИЛЬ.снимок(Path(версия['корень'])) != версия['снимок']:
            raise RuntimeError('изменились замороженные исходники')
    if ПРОФИЛЬ.снимок(Path(общий['корпус']), True) != общий['снимок_корпуса']:
        raise RuntimeError('изменился корпус')
    if ПРОФИЛЬ.состояние_репозитория(Path(общий['корень'])) != общий['состояние_рабочего_репозитория']:
        raise RuntimeError('изменился рабочий Git')


def работник(параметры):
    данные = параметры.план.read_bytes()
    if ПРОФИЛЬ.хэш(данные) != параметры.sha256_плана:
        raise RuntimeError('изменился независимый SHA плана')
    план = json.loads(данные)
    проверить_вход(план)
    общий = план['общий']
    корень = Path(общий['версии']['B']['корень'])
    корпус = Path(общий['корпус'])
    if параметры.версия == 'диагностика':
        модуль = ПРОФИЛЬ.загрузить(корень)
        текст = (корпус / общий['прямые_входы']['частые_ссылки']).read_text()
        исходы, статистика = [], []
        for версия in ('A', 'B'):
            запись = план['процедуры'][версия]
            процедура = загрузить_процедуру(Path(запись['путь']), запись['sha256'])
            выход = параметры.выход.with_suffix('.' + версия + '.pstats')
            результат = процедура.измерить(lambda: модуль._markdown_link_tokens(текст), True, выход)
            исходы.append(процедура.поля(результат['исход']['значение']))
            чтение = pstats.Stats(str(выход))
            статистика.append({'версия': версия, 'читается_pstats': True, 'функций': len(чтение.stats),
                               'байтов': выход.stat().st_size, 'режим': oct(stat.S_IMODE(выход.stat().st_mode))})
        if исходы[0] != исходы[1]:
            raise RuntimeError('различаются диагностические исходы')
        ПРОФИЛЬ.сохранить(параметры.выход, ПРОФИЛЬ.байты({'статистика': статистика}))
        метаданные = {'диагностика': статистика}
    else:
        запись = план['процедуры'][параметры.версия]
        процедура = загрузить_процедуру(Path(запись['путь']), запись['sha256'])
        ограда = None
        if параметры.версия == 'B':
            _, ограда = этап(lambda: процедура.проверить_выходы([параметры.выход]))
        модуль, подготовка = этап(lambda: процедура.загрузить(корень))
        тексты = {имя: (корпус / путь).read_text() for имя, путь in общий['прямые_входы'].items()}
        результаты = {'структура': процедура.измерить(lambda: модуль.validate_layout(корпус), False, параметры.выход.with_suffix('.validate.pstats'))}
        for имя, текст in тексты.items():
            результат = процедура.измерить(lambda: модуль._markdown_link_tokens(текст), False, параметры.выход.with_suffix('.' + имя + '.pstats'))
            if результат['исход']['вид'] == 'результат':
                результат['исход']['значение'] = процедура.поля(результат['исход']['значение'])
            результаты[имя] = результат
        исходы = {имя: запись['исход'] for имя, запись in результаты.items()}
        if any(з['вид'] != 'результат' for з in исходы.values()):
            raise RuntimeError('предметный вызов отказал')
        данные = процедура.байты(исходы)
        _, сохранение = этап(lambda: процедура.сохранить(параметры.выход, данные))
        метаданные = {'версия': параметры.версия, 'sha256_процедуры': запись['sha256'],
                      'обычные_нс': {имя: запись['нс'] for имя, запись in результаты.items()},
                      'границы_нс': {'ограда': ограда, 'импорт_и_подготовка_helper': подготовка, 'сохранение_json': сохранение},
                      'sha256_полных_исходов': процедура.хэш(данные)}
    проверить_вход(план)
    метаданные['питон'] = sys.version
    print(ПРОФИЛЬ.байты(метаданные).decode(), end='')
    return 0


def малый_профиль(параметры):
    """Один ABBA процедур при общем production B; старые 24 образца не вызываются."""
    ось = параметры.приватный.resolve(strict=True)
    if stat.S_IMODE(ось.stat().st_mode) != 0o700 or list(ось.iterdir()):
        raise RuntimeError('нужен новый пустой приватный каталог 0700')
    if any((п / '.git').exists() for п in (ось, *ось.parents)):
        raise RuntimeError('сырые материалы должны находиться вне Git')
    драйвер = ось / Path(__file__).name
    имена = {'A': ось / 'процедура-A.py', 'B': ось / ПУТЬ.name}
    план_путь = ось / 'малый-план.json'
    выходы = [ось / f'обычный-{номер}.json' for номер in range(1, 5)] + [ось / 'диагностика.json']
    состав = [параметры.выход, драйвер, *имена.values(), план_путь, ось / 'общий' / 'план.json', ось / 'общий' / 'процедура.py']
    for выход in выходы:
        состав.extend([выход, выход.with_suffix('.stdout'), выход.with_suffix('.stderr'), выход.with_suffix('.процесс.json')])
    состав.extend(выходы[-1].with_suffix('.' + в + '.pstats') for в in ('A', 'B'))
    контроль = ось / 'контроль-раннего-отказа.json'
    состав.append(контроль)
    _, ограда = этап(lambda: ПРОФИЛЬ.проверить_выходы(состав))
    ПРОФИЛЬ.сохранить(контроль, b'preserve control fixture\n')
    до = (контроль.read_bytes(), контроль.stat().st_mode, контроль.stat().st_ino)
    начало = time.perf_counter_ns()
    try:
        ПРОФИЛЬ.проверить_выходы([контроль])
    except FileExistsError:
        отказ_нс = time.perf_counter_ns() - начало
    else:
        raise RuntimeError('занятый контрольный выход принят')
    if до != (контроль.read_bytes(), контроль.stat().st_mode, контроль.stat().st_ino):
        raise RuntimeError('ранний отказ изменил контрольный файл')
    def подготовка():
        байты_прежней_процедуры = ПРОФИЛЬ.прочитать_репозиторий(параметры.корень, 'show', '8f5e8529f301fd5970f59ace39d5ff6eb36c355e:' + ПУТЬ.relative_to(параметры.корень).as_posix())
        байты_новой_процедуры = ПУТЬ.read_bytes()
        процедуры = {}
        for версия, данные in (('A', байты_прежней_процедуры), ('B', байты_новой_процедуры)):
            ПРОФИЛЬ.сохранить(имена[версия], данные)
            имена[версия].chmod(0o400)
            процедуры[версия] = {'путь': str(имена[версия]), 'sha256': ПРОФИЛЬ.хэш(данные)}
        ПРОФИЛЬ.сохранить(драйвер, Path(__file__).read_bytes())
        драйвер.chmod(0o400)
        общий = ось / 'общий'
        общий.mkdir(mode=0o700)
        план, _ = ПРОФИЛЬ.подготовить(SimpleNamespace(корень=параметры.корень, приватный=общий,
             кандидат=параметры.корень / ПРОФИЛЬ.ЛЕКСЕР, хэш_кандидата=параметры.sha256_лексера))
        корпус = Path(план['корпус'])
        малые_тексты = {'без_ссылок': 'открытая строка без ссылок ' * 40 + '\n',
                       'частые_ссылки': '[x](цель.md) ![y](<цель.md> "t")\n[r]: <цель.md> "t"\n' * 10,
                       'метки_с_кодом': '[a `x`](цель.md) [a [b](цель.md) `x`](цель.md)\n' * 12}
        for имя, текст in малые_тексты.items():
            (корпус / план['прямые_входы'][имя]).write_text(текст)
        for аргументы in (['add', '--', *план['прямые_входы'].values()], ['commit', '-qm', 'Подготовить малый открытый корпус']):
            subprocess.run(['git', *аргументы], cwd=корпус, env=ПРОФИЛЬ.среда(), check=True, capture_output=True)
        план['снимок_корпуса'] = ПРОФИЛЬ.снимок(корпус, True)
        return {'общий': план, 'процедуры': процедуры, 'драйвер': {'путь': str(драйвер), 'sha256': ПРОФИЛЬ.хэш(драйвер.read_bytes())}}
    план, подготовка_нс = этап(подготовка)
    ПРОФИЛЬ.сохранить(план_путь, ПРОФИЛЬ.байты(план))
    план_путь.chmod(0o400)
    хэш_плана = ПРОФИЛЬ.хэш(план_путь.read_bytes())
    образцы, процессы = [], []
    for номер, (версия, выход) in enumerate(zip((*'ABBA', 'диагностика'), выходы), 1):
        команда = [sys.executable, '-I', '-B', str(драйвер), 'работник', '--план', str(план_путь), '--sha256-плана', хэш_плана, '--версия', версия, '--выход', str(выход)]
        процесс, длительность = этап(lambda: subprocess.run(команда, cwd=план['общий']['корпус'], env=ПРОФИЛЬ.среда(), capture_output=True))
        ПРОФИЛЬ.сохранить(выход.with_suffix('.stdout'), процесс.stdout)
        ПРОФИЛЬ.сохранить(выход.with_suffix('.stderr'), процесс.stderr)
        запись = {'порядок': номер, 'версия': версия, 'код': процесс.returncode, 'нс_процесса': длительность,
                  'sha256_stdout': ПРОФИЛЬ.хэш(процесс.stdout), 'sha256_stderr': ПРОФИЛЬ.хэш(процесс.stderr)}
        ПРОФИЛЬ.сохранить(выход.with_suffix('.процесс.json'), ПРОФИЛЬ.байты(запись | {'argv': команда}))
        if процесс.returncode != 0:
            raise RuntimeError('отказал малый профильный процесс ' + str(номер))
        метаданные = json.loads(процесс.stdout)
        if метаданные['питон'] != sys.version:
            raise RuntimeError('не совпала версия Python')
        процессы.append(запись)
        образцы.append(метаданные)
    проверить_вход(план)
    if план_путь.read_bytes() != ПРОФИЛЬ.байты(план):
        raise RuntimeError('изменился малый план')
    исходы = выходы[0].read_bytes()
    if any(выход.read_bytes() != исходы for выход in выходы[1:4]):
        raise RuntimeError('не совпали полные обычные исходы')
    интервалы = []
    for версия in ('A', 'B'):
        выбранные = [з for з in образцы[:4] if з['версия'] == версия]
        измерения = {}
        for имя in выбранные[0]['обычные_нс']:
            времена = [з['обычные_нс'][имя] for з in выбранные]
            измерения[имя] = {'исходные_нс': времена, 'минимум_нс': min(времена), 'максимум_нс': max(времена), 'медиана_нс': statistics.median(времена)}
        интервалы.append({'версия': версия, 'измерения': измерения})
    результат = {'схема': 'fum.малый-профиль-защиты-выходов.1',
        'процедуры': [{'версия': в, 'sha256': з['sha256']} for в, з in план['процедуры'].items()],
        'sha256_драйвера': план['драйвер']['sha256'], 'sha256_лексера': параметры.sha256_лексера,
        'sha256_корпуса': ПРОФИЛЬ.хэш(ПРОФИЛЬ.байты(план['общий']['снимок_корпуса'])),
        'корпус': {'файлов': sum(з[1] is not None for з in план['общий']['снимок_корпуса']['файлы'].values()),
                   'байтов': sum((Path(план['общий']['корпус']) / п).stat().st_size for п, з in план['общий']['снимок_корпуса']['файлы'].items() if з[1] is not None),
                   'повторов_в_прямых_входах': {'без_ссылок': 40, 'частые_ссылки': 10, 'метки_с_кодом': 12}},
        'ранний_отказ': {'нс': отказ_нс, 'исход': 'FileExistsError', 'контрольный_файл_сохранён': True,
                        'граница': 'Прямой вызов раннего guard; setup и workers не вызываются'},
        'общие_границы_нс': {'ограда_до_подготовки': ограда, 'замораживание_и_подготовка_корпуса': подготовка_нс},
        'штатные_образцы': образцы[:4], 'интервалы': интервалы, 'диагностика': образцы[-1], 'процессы': процессы,
        'сверка': {'полные_исходы_равны': True, 'входы_и_Git_неизменны': True, 'sha256_полных_исходов': ПРОФИЛЬ.хэш(исходы)},
        'границы': ['Один ABBA: четыре свежих обычных процесса; один отдельный диагностический процесс',
                     'Обе процедуры вызывают один production lexer и общий физический корпус',
                     'Обычный perf_counter_ns предметного вызова прежний, без Mock и cProfile',
                     'Ограда, импорт и сохранение измерены отдельно; отсутствующая ограда A имеет null',
                     'Сериализация, контрольные снимки, подготовка корпуса и процессы вне обычного таймера',
                     'Малый профиль не доказывает ускорение и не повторяет историческую серию из 24 процессов']}
    ПРОФИЛЬ.сохранить(параметры.выход, ПРОФИЛЬ.байты(результат))
    параметры.выход.chmod(0o644)
    print(json.dumps({'обычных_процессов': 4, 'диагностических_процессов': 1, 'полные_исходы_равны': True}, ensure_ascii=False))
    return 0


def профильная_команда():
    разбор = argparse.ArgumentParser(description=__doc__)

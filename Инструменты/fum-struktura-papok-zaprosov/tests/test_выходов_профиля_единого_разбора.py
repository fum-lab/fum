    малый.add_argument('--корень', type=Path, required=True)
    малый.add_argument('--приватный', type=Path, required=True)
    малый.add_argument('--sha256-лексера', required=True)
    малый.add_argument('--выход', type=Path, required=True)
    дочерний = команды.add_parser('работник')
    дочерний.add_argument('--план', type=Path, required=True)
    дочерний.add_argument('--sha256-плана', required=True)

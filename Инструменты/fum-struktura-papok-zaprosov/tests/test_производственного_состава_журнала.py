    def test_независимые_идентичности_и_выбор_не_подменяются(сам):
        случаи = [('исполнитель', сам.фикс.координатор), ('координатор', сам.фикс.исполнитель),
            ('ветка', 'refs/heads/codex/foreign'), ('корень', str(сам.фикс.корень.parent))]
        for поле, значение in случаи:
            with сам.subTest(поле=поле):
                вход = copy.deepcopy(сам.фикс.вход); вход[поле] = значение
                до = сам.фикс.снимок()

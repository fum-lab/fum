ИСХОДНИКИ = (ПУТЬ_КОДА, *ИСХОДНИКИ_УСТАНОВЩИКА)


def загрузить():
    описание = importlib.util.spec_from_file_location('восстановитель_режимов_для_проверки', КОРЕНЬ / ПУТЬ_КОДА)
    модуль = importlib.util.module_from_spec(описание)
    sys.modules[описание.name] = модуль
    описание.loader.exec_module(модуль)
    return модуль


class Фикстура:
    def __init__(сам):
        сам.процессы = []
        сам.основа = Основа()
        сам.корень = сам.основа.root.resolve()
        сам.основа.git('checkout', '-qb', 'codex/восстановление')
        for имя in ИСХОДНИКИ:
            сам.основа.write(имя, (КОРЕНЬ / имя).read_bytes())
        сам.основа.commit()
        сам.код = сам.основа.git('rev-parse', 'HEAD').stdout.strip()
        сам.цели = []
        сам.основа.write('Журнал/README.md', '# Журнал\n')
        for номер in range(7):
            папка = 'Журнал/2026-10-01_12-00-0' + str(номер) + '_MSK_исправить-пару-' + str(номер)
            for имя in ('запрос.md', 'отчёт.md'):
                путь = сам.основа.write(папка + '/' + имя, '# Публичный документ\n').resolve()
                if имя == 'отчёт.md' or номер == 3:
                    # Историческое создание: режим 0600 возникает до Git,
                    # без chmod публичного файла при подготовке снимка H.
                    with tempfile.NamedTemporaryFile(dir=путь.parent, delete=False) as поток:
                        поток.write(путь.read_bytes())
                        временный = Path(поток.name)
                    временный.replace(путь)
                    сам.цели.append(путь.relative_to(сам.корень).as_posix())
        сам.материал = сам.основа.write(Path(папка) / 'материалы' / 'история-модели.json', '"материал"\n', 0o600).resolve()
        сам.основа.commit()
        сам.принятый = сам.основа.git('rev-parse', 'HEAD').stdout.strip()
        сам.приватная = tempfile.TemporaryDirectory()
        сам.приватный = Path(сам.приватная.name).resolve()
        сам.приватный.chmod(0o700)
        сам.каталог = сам.приватный / 'состояние'
        сам.каталог.mkdir(mode=0o700)
        сам.данные = {
            'схема': 'fum.выбор-восстановления-режимов-пар.1',
            'координатор': os.environ['CODEX_THREAD_ID'], 'корень': str(сам.корень),
            'ветка': 'refs/heads/codex/восстановление',
            'принятый_коммит': сам.принятый,
            'принятое_дерево': сам.основа.git('rev-parse', 'HEAD^{tree}').stdout.strip(),
            'код': {'коммит': сам.код, 'путь': ПУТЬ_КОДА,
                'sha256': hashlib.sha256((КОРЕНЬ / ПУТЬ_КОДА).read_bytes()).hexdigest()},
            'каталог_состояния': str(сам.каталог),
            'цели': [{'путь': имя,
                'blob': сам.основа.git('rev-parse', сам.принятый + ':' + имя).stdout.strip(),
                'sha256': hashlib.sha256((сам.корень / имя).read_bytes()).hexdigest()}
                for имя in сам.цели]}
        сам.выбор = сохранить(сам.приватный / 'выбор.json', сам.данные)
        сам.модуль = загрузить()

    def план(сам):
        return сохранить(сам.приватный / 'план.json', сам.модуль.построить_план(сам.выбор))

    def другой_выбор(сам, данные):
        номер = len(list(сам.приватный.glob('выбор-*.json')))
        return сохранить(сам.приватный / ('выбор-' + str(номер) + '.json'), данные)

    def работник(сам, план, *, режим='применить', завершение=None, точка=None, ждать=False):
        вход = {'план': план, 'выбор': сам.выбор, 'режим': режим,
            'завершение': завершение, 'точка': точка, 'ждать': ждать}
        путь = сам.приватный / ('работник-' + str(len(list(сам.приватный.glob('работник-*')))) + '.json')
        сохранить(путь, вход)
        процесс = subprocess.Popen([sys.executable, '-B', str(Path(__file__).resolve()), '--работник', str(путь)],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        сам.процессы.append(процесс)
        return процесс

    def завершение(сам, процесс):
        assert процесс.poll() == 0
        квитанция = сам.каталог / 'квитанция.json'
        return сохранить(сам.приватный / ('завершение-' + str(процесс.pid) + '.json'), {
            'схема': 'fum.завершение-восстановления-режимов-пар.1',
            'процесс': процесс.pid, 'код_завершения': 0,
            'квитанция_sha256': hashlib.sha256(квитанция.read_bytes()).hexdigest()})

    def закрыть(сам):
        for процесс in сам.процессы:
            if процесс.poll() is None:
                процесс.kill()
            процесс.communicate(timeout=5)
        сам.основа.close()
        сам.приватная.cleanup()


class ВосстановлениеРежимов(unittest.TestCase):
    def setUp(сам):
        сам.среда = patch.dict(os.environ, {'CODEX_THREAD_ID': '00000000-0000-0000-0000-000000000001'})
        сам.среда.start()
        сам.ф = Фикстура()

    def tearDown(сам):
        сам.ф.закрыть()
        сам.среда.stop()

    def test_реальные_восемь_пар_0600_в_0644_и_свежий_повтор(сам):
        ф = сам.ф
        до = наблюдение(ф.корень)
        план = ф.план()
        сам.assertEqual(наблюдение(ф.корень), до)
        первый = ф.работник(план)
        вывод, ошибка = первый.communicate(timeout=30)
        сам.assertEqual(первый.returncode, 0, ошибка)
        сам.assertEqual(json.loads(вывод)['записей'], 8)
        после = наблюдение(ф.корень)
        for имя in до:
            if имя not in ф.цели:
                сам.assertEqual(после[имя], до[имя], имя)
            else:
                сам.assertEqual(до[имя][1], 0o600)
                сам.assertEqual(после[имя][1], 0o644)
                сам.assertEqual(после[имя][:1] + после[имя][2:5] + после[имя][6:],
                    до[имя][:1] + до[имя][2:5] + до[имя][6:], имя)
        завершение = ф.завершение(первый)
        приватное = наблюдение(ф.каталог)
        второй = ф.работник(план, режим='повтор', завершение=завершение)
        вывод, ошибка = второй.communicate(timeout=30)
        сам.assertEqual(второй.returncode, 0, ошибка)
        сам.assertNotEqual(первый.pid, второй.pid)
        сам.assertEqual(json.loads(вывод)['записей'], 0)
        сам.assertEqual(наблюдение(ф.корень), после)
        сам.assertEqual(наблюдение(ф.каталог), приватное)
        сам.assertEqual(stat.S_IMODE(ф.материал.stat().st_mode), 0o600)

    def test_нерасширяемая_область_независимого_выбора(сам):
        ф = сам.ф
        варианты = []
        for поле, значение in (('ветка', 'refs/heads/master'), ('принятое_дерево', '0' * 40),
                ('координатор', '00000000-0000-0000-0000-000000000002')):
            данные = deepcopy(ф.данные); данные[поле] = значение; варианты.append(данные)
        for цели in (ф.данные['цели'][:7], ф.данные['цели'] + ф.данные['цели'][:1],
                ф.данные['цели'][:7] + ф.данные['цели'][:1]):
            данные = deepcopy(ф.данные); данные['цели'] = цели; варианты.append(данные)
        for имя in ('Журнал/README.md', ф.материал.relative_to(ф.корень).as_posix(),
                '../приватное/запрос.md', ф.цели[0].replace('Журнал/', 'журнал/'),
                'Журнал/нет-пары/отчёт.md'):
            данные = deepcopy(ф.данные); данные['цели'][0]['путь'] = имя; варианты.append(данные)
        данные = deepcopy(ф.данные); данные['цели'][0]['blob'] = '0' * 40; варианты.append(данные)
        данные = deepcopy(ф.данные); данные['код']['sha256'] = '0' * 64; варианты.append(данные)
        до, служебное = наблюдение(ф.корень), наблюдение(ф.каталог)
        for данные in варианты:
            with сам.subTest(данные=данные):
                with сам.assertRaises((ValueError, OSError)):
                    ф.модуль.построить_план(ф.другой_выбор(данные))
                сам.assertEqual(наблюдение(ф.корень), до)
                сам.assertEqual(наблюдение(ф.каталог), служебное)

    def test_режимы_ссылки_и_байты_не_принимаются_по_сходству(сам):
        ф = сам.ф
        цель = ф.корень / ф.цели[0]
        for режим in (0o400, 0o444, 0o644, 0o664, 0o700, 0o755, 0o1600):
            цель.chmod(режим)
            до = наблюдение(ф.корень)
            with сам.assertRaises(ValueError):
                ф.модуль.построить_план(ф.выбор)
            сам.assertEqual(наблюдение(ф.корень), до)
        цель.chmod(0o600)
        ссылка = цель.with_name('ещё-одна-ссылка')
        os.link(цель, ссылка)
        with сам.assertRaises(ValueError):
            ф.модуль.построить_план(ф.выбор)
        ссылка.unlink()
        сырые = цель.read_bytes()
        цель.unlink(); цель.symlink_to(ф.материал)
        with сам.assertRaises(ValueError):
            ф.модуль.построить_план(ф.выбор)
        цель.unlink(); цель.write_bytes(сырые + b'!'); цель.chmod(0o600)
        with сам.assertRaises(ValueError):
            ф.модуль.построить_план(ф.выбор)
        сам.assertFalse(list(ф.каталог.iterdir()))


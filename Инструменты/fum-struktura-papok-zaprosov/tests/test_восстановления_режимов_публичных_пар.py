def выполнить_работника(путь):
    вход = json.loads(Path(путь).read_bytes())
    модуль = загрузить()

    def отказ(точка):
        if точка == вход['точка']:
            if вход['ждать']:
                print('готово', flush=True)
                sys.stdin.read(1)
            else:
                os._exit(73)
    try:
        if вход['режим'] == 'повтор':
            итог = модуль.повтор(вход['план'], вход['выбор'], вход['завершение'])
        else:
            итог = модуль.применить(вход['план'], вход['выбор'], отказ=отказ)
        print(json.dumps(итог, ensure_ascii=False))
        return 0
    except (ValueError, OSError) as ошибка:
        print(str(ошибка), file=sys.stderr)
        return 2



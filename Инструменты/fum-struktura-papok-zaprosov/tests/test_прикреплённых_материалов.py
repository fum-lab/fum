"""Наполнение собственной пары сохраняет прикрепления и границы разделов."""
import unittest

import test_наполнения_карточки as основа


class ПроверкаПрикреплённыхМатериалов(unittest.TestCase):
    def setUp(сам):
        сам.пример = основа.ПроверкаНаполненияКарточки()
        сам.пример.setUp()
        сам.addCleanup(сам.пример.doCleanups)
        сам.прикрепления = (
            '\n## Прикрепляемые материалы\n\n'
            '- [Открытый источник](../../вход.txt) — ё, пробелы и исходный порядок.\n'
            '\n````text\n## Повлиял на файлы\nЭто содержимое источника.\n````\n'
            '\n<!-- Обычный комментарий источника -->\n'
        ).encode()

    def заполнить(сам):
        п = сам.пример
        return п.модуль.применить(п.корень, п.вход, п.модуль.подготовить(п.корень, п.вход))

    def test_первый_повторный_и_обновлённый_рендер_сохраняют_прикрепления(сам):
        п = сам.пример
        п.запрос.write_bytes(п.запрос.read_bytes() + сам.прикрепления)
        до = п.снимок()
        сам.assertEqual(сам.заполнить()['изменено'], 2)
        сам.assertTrue(п.запрос.read_bytes().endswith(сам.прикрепления))
        файлы = [(f.stat().st_ino, f.stat().st_mtime_ns, f.read_bytes())
                 for f in (п.запрос, п.отчёт)]
        сам.assertEqual(сам.заполнить()['изменено'], 0)
        сам.assertEqual(файлы, [(f.stat().st_ino, f.stat().st_mtime_ns, f.read_bytes())
                               for f in (п.запрос, п.отчёт)])
        п.вход['инструменты'][0]['версия'] = 'Новая версия открытой фикстуры'
        сам.assertEqual(сам.заполнить()['изменено'], 1)
        сам.assertTrue(п.запрос.read_bytes().endswith(сам.прикрепления))
        сам.assertEqual(п.снимок()[2:], до[2:])

    def test_дубли_неверное_место_и_неизвестный_раздел_не_меняют_пару(сам):
        п = сам.пример
        оригинал = п.запрос.read_bytes()
        варианты = [
            оригинал + сам.прикрепления + сам.прикрепления,
            оригинал.replace('## Текст запроса'.encode(),
                              сам.прикрепления + '\n## Текст запроса'.encode(), 1),
            оригинал + сам.прикрепления + '\n## Другой раздел\n'.encode(),
        ]
        for вариант in варианты:
            with сам.subTest(вариант=варианты.index(вариант)):
                п.запрос.write_bytes(вариант)
                до = п.снимок()
                with сам.assertRaises(ValueError):
                    сам.заполнить()
                сам.assertEqual(п.снимок(), до)

    def test_прикрепления_в_отчёте_не_ослабляют_его_схему(сам):
        п = сам.пример
        п.отчёт.write_bytes(п.отчёт.read_bytes() + сам.прикрепления)
        до = п.снимок()
        with сам.assertRaises(ValueError):
            сам.заполнить()
        сам.assertEqual(п.снимок(), до)

    def test_граница_генерируемого_состава_не_поглощает_прикрепления(сам):
        п = сам.пример
        п.запрос.write_bytes(п.запрос.read_bytes() + сам.прикрепления)
        сам.заполнить()
        конец = '<!-- FUM-КАРТОЧКА:КОНЕЦ состав -->\n'.encode()
        данные = п.запрос.read_bytes()
        сам.assertEqual(данные.count(конец), 1)
        п.запрос.write_bytes(данные.replace(конец, b'', 1) + конец)
        до = п.снимок()
        with сам.assertRaises(ValueError):
            сам.заполнить()
        сам.assertEqual(п.снимок(), до)


if __name__ == '__main__':
    unittest.main()

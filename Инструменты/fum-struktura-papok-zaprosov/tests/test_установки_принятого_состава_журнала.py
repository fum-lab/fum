    def test_пара_устанавливается_и_свежий_повтор_не_пишет(сам):
        ф = сам.фикстура
        план = ф.план()
        история = наблюдение(ф.корень / 'Журнал')
        первый = ф.работник(план)
        вывод, ошибка = первый.communicate(timeout=30)
        сам.assertEqual(первый.returncode, 0, ошибка)
        сам.assertFalse(json.loads(вывод)['результат']['повтор'])
        до, состояние_до = наблюдение(ф.корень), наблюдение(ф.каталог)
        второй = ф.работник(план, режим='повтор', завершение=ф.завершение(первый))
        вывод, ошибка = второй.communicate(timeout=30)
        сам.assertEqual(второй.returncode, 0, ошибка)
        сам.assertNotEqual(первый.pid, второй.pid)
        сам.assertTrue(json.loads(вывод)['результат']['повтор'])
        сам.assertEqual(наблюдение(ф.корень), до)
        сам.assertEqual(наблюдение(ф.каталог), состояние_до)
        сам.assertEqual(наблюдение(ф.корень / 'Журнал'), история)

    def test_исторический_материал_0600_устанавливается_без_смены_режима(сам):
        сам.фикстура.закрыть()
        сам.фикстура = Фикстура(материал_0600=True)

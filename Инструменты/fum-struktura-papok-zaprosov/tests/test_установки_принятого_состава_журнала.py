        план = ф.план()
        первый = ф.работник(план)
        вывод, ошибка = первый.communicate(timeout=30)
        сам.assertEqual(первый.returncode, 0, ошибка)
        сам.assertEqual(json.loads(вывод)['результат']['записей'], 2)
        завершение = ф.завершение(первый)
        до, приватное = наблюдение(ф.корень), наблюдение(ф.каталог)

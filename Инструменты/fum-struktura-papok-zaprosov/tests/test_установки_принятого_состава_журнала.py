def выполнить_работника(путь):
    вход = json.loads(Path(путь).read_bytes())
    модуль = загрузить_установщик(Path(вход['корень_кода']) if вход['корень_кода'] else КОРЕНЬ)
    if вход['сбой_синхронизации']:
        исходная = модуль.синхронизировать
        def с_отказом(каталог):
            if каталог == Path(вход['каталог']) and (каталог / 'квитанция.json').exists():
                raise OSError('внедрён отказ финального fsync каталога')
            return исходная(каталог)
        модуль.синхронизировать = с_отказом

    def отказ(точка):
        if точка != вход['точка']:
            return
        if вход['заменить_узел'] is not None:
            заменить_тот_же_файл(Path(вход['заменить_узел']))
            return
        if вход['сменить_режим'] is not None:
            Path(вход['сменить_режим']).chmod(0o600)
            return
        if вход['чужой'] is not None:
            Path(вход['чужой']).write_bytes('поздние чужие байты'.encode())
            return
        if вход['ждать']:
            print('готово', flush=True)
            sys.stdin.read(1)
        else:
            os._exit(73)

    try:
        аргументы = (вход['план'], вход['выбор'], вход['каталог'])
        if вход['режим'] == 'восстановить':
            итог = модуль.восстановить(*аргументы, вход['остановка'], отказ=отказ)
        elif вход['режим'] == 'повтор':
            итог = модуль.повтор(*аргументы, вход['завершение'])
        else:
            итог = модуль.применить(*аргументы, отказ=отказ)
        print(json.dumps({'процесс': os.getpid(), 'результат': итог}, ensure_ascii=False))
        return 0
    except (ValueError, OSError) as ошибка:
        print(str(ошибка), file=sys.stderr)
        return 2



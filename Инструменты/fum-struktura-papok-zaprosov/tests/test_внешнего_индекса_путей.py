class ВнешнийИндекс(unittest.TestCase):
    def test_реальные_ранний_проход_и_proof_не_перечисляют_общего_предка_на_каждый_путь(сам):
        sys.path.insert(0, str(КОРЕНЬ / 'Инструменты/fum-svyaznostj-rabochej-sessii/tests'))
        import test_двух_общих_проходов as фикстуры
        м = связность.журнал(); класс = м.ИндексПутей
        for количество in (4, 8, 16):
            with сам.subTest(каталогов=количество), фикстуры.стенд(2,
                    внешний_корпус=количество) as (р, параметры):
                широкий = р.ф.корень / 'Внешнее/общий/wide'
                до = фикстуры.снимок(р)
                счёт = {}; активный = [None]
                исходное = Path.iterdir
                совпадения = класс.совпадения; проверить = класс.проверить
                @contextmanager
                def область(индекс):
                    прежний = активный[0]; активный[0] = индекс
                    try:
                        yield
                    finally:
                        активный[0] = прежний
                def поиск(индекс, *аргументы):
                    with область(индекс):
                        return совпадения(индекс, *аргументы)
                def сверка(индекс):
                    with область(индекс):
                        return проверить(индекс)
                def перечисление(путь):
                    if путь == широкий:
                        сам.assertIsNotNone(активный[0], 'неиндексированное перечисление')
                        счёт.setdefault(активный[0], [0, 0])[0] += 1
                    for ребёнок in исходное(путь):
                        if путь == широкий:
                            счёт[активный[0]][1] += 1
                        yield ребёнок
                with patch.object(класс, 'совпадения', поиск), \
                        patch.object(класс, 'проверить', сверка), \
                        patch.object(Path, 'iterdir', перечисление):
                    for имя in фикстуры.АПИ:
                        фикстуры.вызвать(связность, имя, параметры, р.выбранный)
                сам.assertGreaterEqual(len(счёт), 5)
                сам.assertTrue(all(с == [2, 2 * количество] for с in счёт.values()), счёт)
                сам.assertEqual(фикстуры.снимок(р), до)

    def test_общие_широкие_предки_не_перечитываются_при_расширении(сам):
        м = связность.журнал()
        for количество in (16, 32, 64):
            with сам.subTest(каталогов=количество), tempfile.TemporaryDirectory() as временный:
                корень = Path(временный).resolve()
                широкий = корень / 'Код' / 'общий'
                широкий.mkdir(parents=True)
                имена = []
                for н in range(количество):
                    каталог = широкий / ('пакет-%04d' % н)
                    каталог.mkdir()
                    for имя in ('а.txt', 'б.txt'):
                        файл = каталог / имя
                        файл.write_bytes(b'x')
                        имена.append(файл.relative_to(корень).as_posix())
                исходный = Path.iterdir
                счёт = {'перечислений': 0, 'имён': 0}
                def перечисление(путь):
                    if путь == широкий:
                        счёт['перечислений'] += 1
                    for ребёнок in исходный(путь):
                        if путь == широкий:
                            счёт['имён'] += 1
                        yield ребёнок
                with patch.object(Path, 'iterdir', перечисление):
                    with м.ИндексПутей(корень, м.контракт.ключ_коллизии,
                            внешние_родители=True) as индекс:
                        for _ in range(2):
                            for имя in имена:
                                сам.assertEqual(м.точный_путь(корень, имя,
                                    существует=True, индекс=индекс), корень / имя)
                        сам.assertEqual(счёт, {'перечислений': 1, 'имён': количество})
                    сам.assertEqual(счёт, {'перечислений': 2, 'имён': 2 * количество})

    def test_поздний_дрейф_внешнего_родителя_и_посещённых_узлов(сам):
        м = связность.журнал()
        for действие in ('добавить', 'удалить', 'rename', 'inode', 'mode',
                'nlink', 'symlink', 'байты', 'родитель'):
            with сам.subTest(действие=действие), tempfile.TemporaryDirectory() as временный:
                корень = Path(временный).resolve()
                каталог = корень / 'Код'; каталог.mkdir()
                файл = каталог / 'текст'; файл.write_bytes(b'a'); файл.chmod(0o644)
                with сам.assertRaises((ValueError, OSError)):
                    with м.ИндексПутей(корень, м.контракт.ключ_коллизии,
                            внешние_родители=True) as индекс:
                        м.точный_путь(корень, 'Код/текст', существует=True, индекс=индекс)
                        if действие == 'добавить': (каталог / 'поздний').mkdir()
                        elif действие == 'удалить': файл.unlink()
                        elif действие == 'rename': файл.rename(файл.with_name('новый'))
                        elif действие == 'inode':
                            новый = файл.with_name('другой'); новый.write_bytes(b'a'); новый.replace(файл)
                        elif действие == 'mode': файл.chmod(0o600)
                        elif действие == 'nlink': os.link(файл, файл.with_name('ссылка'))
                        elif действие == 'symlink': файл.unlink(); файл.symlink_to(os.devnull)
                        elif действие == 'байты': файл.write_bytes(b'b')
                        elif действие == 'родитель':
                            каталог.rename(корень / 'прежний'); каталог.mkdir()
                            (каталог / 'текст').write_bytes(b'a')

    def test_первичная_ошибка_сохраняется_при_позднем_дрейфе(сам):
        м = связность.журнал()
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный).resolve(); (корень / 'Код').mkdir()
            файл = корень / 'Код/текст'; файл.write_bytes(b'a')
            первичная = RuntimeError('исходный отказ')
            with сам.assertRaises(RuntimeError) as поймана:
                with м.ИндексПутей(корень, м.контракт.ключ_коллизии,
                        внешние_родители=True) as индекс:
                    м.точный_путь(корень, 'Код/текст', индекс=индекс)
                    файл.unlink()
                    raise первичная
            сам.assertIs(поймана.exception, первичная)
            with сам.assertRaises(ValueError):
                индекс.совпадения(корень, 'новый-родитель')

    def test_нет_рекурсии_по_соседям_и_нового_входа_из_локального_состояния(сам):
        м = связность.журнал()
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный).resolve()
            (корень / 'Код/чужое-поддерево').mkdir(parents=True)
            файл = корень / 'Код/выбранный'; файл.write_bytes(b'a')
            посторонний = корень / 'Код/локальный'; посторонний.write_bytes(b'a')
            (корень / '.obsidian').mkdir()
            граф = корень / '.obsidian/graph.json'; граф.write_bytes(b'{}')
            исходный = Path.iterdir
            def перечисление(путь):
                if путь in (корень / 'Код/чужое-поддерево', корень / '.obsidian'):
                    raise PermissionError('соседнее поддерево не вход')
                return исходный(путь)
            with patch.object(Path, 'iterdir', перечисление):
                with м.ИндексПутей(корень, м.контракт.ключ_коллизии,
                        внешние_родители=True) as индекс:
                    м.точный_путь(корень, 'Код/выбранный', индекс=индекс)
                    посторонний.write_bytes(b'changed')
                    граф.write_bytes(b'{"changed":true}')
                    сам.assertEqual(м.точный_путь(корень, 'Нет/ещё-нет', индекс=индекс),
                        корень / 'Нет/ещё-нет')
            with м.ИндексПутей(корень, м.контракт.ключ_коллизии) as прежний:
                with сам.assertRaises(ValueError):
                    прежний.совпадения(корень / 'Код', 'выбранный')

    def test_точные_группы_имён_и_граница_ленивого_родителя(сам):
        м = связность.журнал()
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный).resolve(); каталог = корень / 'Код'; каталог.mkdir()
            файл = каталог / 'точный'; файл.write_bytes(b'a')
            (корень / 'ссылка').symlink_to(каталог, target_is_directory=True)
            исходный = Path.iterdir
            def перечисление(путь):
                if путь == каталог:
                    return iter([файл, каталог / 'Имя', каталог / 'имя',
                        каталог / 'é', каталог / 'e\u0301'])
                return исходный(путь)
            with patch.object(Path, 'iterdir', перечисление):
                with м.ИндексПутей(корень, м.контракт.ключ_коллизии,
                        внешние_родители=True) as индекс:
                    сам.assertEqual(индекс.совпадения(каталог, 'точный'), ['точный'])
                    сам.assertEqual(set(индекс.совпадения(каталог, 'Имя')), {'Имя', 'имя'})
                    сам.assertEqual(set(индекс.совпадения(каталог, 'é')), {'é', 'e\u0301'})
                    with сам.assertRaises(ValueError):
                        м.точный_путь(корень, 'Код/Имя', индекс=индекс)
                    for родитель in (корень.parent, корень / '..', корень / 'ссылка', Path('Код')):
                        with сам.subTest(родитель=str(родитель)), сам.assertRaises(ValueError):
                            индекс.совпадения(родитель, 'точный')
            with сам.assertRaises(ValueError):
                индекс.совпадения(каталог, 'точный')

    def test_инвентарь_и_поздняя_сверка_перечисляют_имена_линейно(сам):
        м = связность.журнал()
        for количество in (16, 32, 64):
            with сам.subTest(файлов=количество), tempfile.TemporaryDirectory() as временный:
                корень = Path(временный).resolve()
                каталог = корень / 'Код' / 'общий'
                каталог.mkdir(parents=True)
                имена = ['Код/общий/файл-%04d.md' % н for н in range(количество)]
                for имя in имена:
                    (корень / имя).write_bytes(b'text\n')
                    (корень / имя).chmod(0o644)
                исходный = Path.iterdir
                счёт = {'перечислений': 0, 'имён': 0}
                def перечисление(путь):
                    if путь == каталог:
                        счёт['перечислений'] += 1
                    for ребёнок in исходный(путь):
                        if путь == каталог:
                            счёт['имён'] += 1
                        yield ребёнок
                def гит(путь, *аргументы, **параметры):
                    сам.assertEqual(путь, корень)
                    сам.assertEqual(аргументы,
                        ('ls-files', '--cached', '--others', '--exclude-standard', '-z'))
                    return ('\0'.join(имена) + '\0').encode()
                снимки = {}
                with patch.object(Path, 'iterdir', перечисление), \
                        patch.object(м, '_гит', гит), \
                        patch.object(связность, 'принятые_материалы_разметки', return_value={}):
                    результат = связность.инвентарь_разметки(корень, снимки=снимки)
                    сам.assertEqual(set(результат), set(имена))
                    сам.assertEqual(счёт, {'перечислений': 2, 'имён': 2 * количество})
                    связность.сверить_снимки_разметки(корень, снимки)
                    сам.assertEqual(счёт, {'перечислений': 4, 'имён': 4 * количество})



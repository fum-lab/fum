"""Ранний сигнал покрытия не требует перевыпуска S после изменения только кода."""
import os
import sys
from pathlib import Path
import unittest
from unittest import mock

import test_локальной_установки_принятого_состава as локальный
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import раннее_покрытие_журнала as ранний


class ПокрытиеСостава(unittest.TestCase):
    def setUp(сам):
        среда = mock.patch.dict(os.environ, {'CODEX_THREAD_ID': '00000000-0000-0000-0000-000000000001'})
        среда.start(); сам.addCleanup(среда.stop)

    def test_изменение_только_кода_не_требует_свежего_S(сам):
        with локальный.локальная_фикстура() as ф:
            ф.основа.write('данные.txt', b'changed\n'); ф.основа.commit()
            вершина = ф.основа.git('rev-parse', 'HEAD').stdout.strip()
            сам.assertNotEqual(вершина, ф.принятый)
            до = локальный.прежние.наблюдение(ф.корень)
            ответ = ранний.проверить(ф.корень, ф.данные_выбора['состав'], вершина)
            сам.assertIs(ответ['покрытие'], True)
            сам.assertIs(ответ['полная_проверка'], False)
            сам.assertEqual(до, локальный.прежние.наблюдение(ф.корень))

    def test_новая_закрытая_пара_обнаруживается_до_полной_проверки(сам):
        with локальный.локальная_фикстура() as ф:
            папка = 'Журнал/2026-10-21_12-00-00_MSK_новая-пара'
            for имя in ('запрос.md', 'отчёт.md'): ф.основа.write(папка + '/' + имя, b'new\n')
            ф.основа.commit(); вершина = ф.основа.git('rev-parse', 'HEAD').stdout.strip()
            with сам.assertRaisesRegex(ValueError, 'состав не покрывает'):
                ранний.проверить(ф.корень, ф.данные_выбора['состав'], вершина)

    def test_дрейф_HEAD_при_чтении_отказывает(сам):
        with локальный.локальная_фикстура() as ф:
            исходный = ранний.журнал._гит
            чтений = 0
            def чтение(корень, *аргументы):
                nonlocal чтений
                if аргументы == ('rev-parse', 'HEAD'):
                    чтений += 1
                    if чтений == 2:
                        return b'1111111111111111111111111111111111111111\n'
                return исходный(корень, *аргументы)
            with mock.patch.object(ранний.журнал, '_гит', side_effect=чтение):
                with сам.assertRaisesRegex(ValueError, 'HEAD изменился при сверке покрытия'):
                    ранний.проверить(ф.корень, ф.данные_выбора['состав'], ф.принятый)

    def test_собственная_незакоммиченная_пара_не_смешивается_с_H(сам):
        with локальный.локальная_фикстура() as ф:
            папка = 'Журнал/2026-10-21_12-00-00_MSK_открытая-пара'
            for имя in ('запрос.md', 'отчёт.md'): ф.основа.write(папка + '/' + имя, b'open\n')
            ответ = ранний.проверить(ф.корень, ф.данные_выбора['состав'], ф.принятый)
            сам.assertIs(ответ['покрытие'], True)


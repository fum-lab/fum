    def test_приватный_читатель_отклоняет_нечастные_и_подменённые_входы(сам):
        путь = сам.частный / 'вход.json'
        путь.write_bytes(модуль.байты({'текст': 'Точный вход'}))
        путь.chmod(0o600)
        сам.assertEqual(модуль.прочитать(str(путь)), {'текст': 'Точный вход'})
        путь.chmod(0o644)
        with сам.assertRaises(ValueError):
            модуль.прочитать(str(путь))
        путь.chmod(0o600)
        сам.частный.chmod(0o755)
        with сам.assertRaises(ValueError):
            модуль.прочитать(str(путь))
        сам.частный.chmod(0o700)
        ссылка = сам.частный / 'ссылка.json'
        ссылка.symlink_to(путь)
        with сам.assertRaises(ValueError):
            модуль.прочитать(str(ссылка))
        ссылка.unlink()
        os.link(путь, ссылка)
        with сам.assertRaises(ValueError):
            модуль.прочитать(str(путь))
        ссылка.unlink()
        (сам.частный / '.git').mkdir()
        with сам.assertRaises(ValueError):
            модуль.прочитать(str(путь))
        (сам.частный / '.git').rmdir()
        путь.write_bytes(b'{"a":1,"a":2}\n')
        with сам.assertRaises(ValueError):
            модуль.прочитать(str(путь))


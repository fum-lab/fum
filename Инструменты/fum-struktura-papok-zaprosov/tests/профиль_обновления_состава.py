"""Повторяемый профиль предпросмотра состава; результат хранится в материалах Журнала."""
from __future__ import annotations

import hashlib
import json
import platform
from pathlib import Path
import statistics
import subprocess
import sys
import time

sys.path.insert(0, str(Path(__file__).parent))
from test_обновить_состав_карточки import ОбновлениеСоставаКарточки


def main() -> None:
    if len(sys.argv) != 2:
        raise ValueError('Укажите один новый путь файла профиля')
    выход = Path(sys.argv[1])
    корень = Path(__file__).resolve().parents[3]
    if (not выход.is_absolute() or выход != выход.resolve() or выход.is_symlink()
            or выход.exists() or not выход.parent.is_dir()
            or выход.parent.is_symlink() or not выход.is_relative_to(корень / 'Журнал')):
        raise ValueError('Профиль сохраняется новым обычным файлом внутри Журнала')

    фикстура = ОбновлениеСоставаКарточки()
    фикстура.setUp()
    try:
        import обновить_состав_карточки as модуль

        исходный_статус = фикстура._git('status', '--porcelain=v1', '--untracked-files=all')
        исходный_запрос = фикстура.запрос.read_bytes()
        измерения = []
        начало_сессии = time.perf_counter_ns()
        for номер in range(7):
            точки = {}
            начало = time.perf_counter_ns()
            план = модуль.подготовить(
                фикстура.корень, фикстура.путь_запроса, фикстура.путь_разрешения,
                профиль=точки,
            )
            длительность = time.perf_counter_ns() - начало
            if фикстура.запрос.read_bytes() != исходный_запрос:
                raise AssertionError('Предпросмотр изменил исходный запрос')
            if фикстура._git('status', '--porcelain=v1', '--untracked-files=all') != исходный_статус:
                raise AssertionError('Предпросмотр изменил Git-состояние фикстуры')
            измерения.append({'номер': номер + 1, 'длительность_нс': длительность,
                              'точки_нс': точки, 'запрос_после_sha256': план['запрос_sha256_до']})

        сводка = {}
        for имя in ('разрешение-и-снимок-git', 'рендер-и-проверка-ссылок', 'повторная-сверка'):
            значения = [запись['точки_нс'][имя] for запись in измерения]
            сводка[имя] = {'медиана_нс': statistics.median(значения),
                           'минимум_нс': min(значения), 'максимум_нс': max(значения)}
        длительности = [запись['длительность_нс'] for запись in измерения]
        общий_максимум = max(длительности)
        решение = ('Оптимизация не обоснована: каждый предпросмотр короче 100 мс на малой фикстуре.'
                   if общий_максимум < 100_000_000 else
                   'Нужен разбор самой дорогой измеренной стадии перед решением об оптимизации.')
        данные = {
            'схема': 'fum.профиль-обновления-состава-карточки.1',
            'исходный_HEAD': subprocess.check_output(
                ['git', '-C', str(корень), 'rev-parse', 'HEAD'], text=True).strip(),
            'интерпретатор': platform.python_version(),
            'архитектура': platform.machine(),
            'профильный_сценарий_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'исходники_sha256': модуль._хэши_исполняемого_контура(),
            'фикстура': {'HEAD': фикстура._git('rev-parse', 'HEAD').decode().strip(),
                         'разрешение_sha256': hashlib.sha256(
                             фикстура.путь_разрешения.read_bytes()).hexdigest(),
                         'число_целей': len(фикстура.вход['разрешённые_цели'])},
            'измерений': len(измерения),
            'длительность_нс': {'медиана': statistics.median(длительности),
                                'минимум': min(длительности), 'максимум': общий_максимум},
            'стадии': сводка,
            'решение_по_оптимизации': решение,
            'ограничение': 'Малая синтетическая Git-фикстура; не измеряет крупный checkout, полный цикл Codex или расход контекста.',
            'измерения': измерения,
            'длительность_профиля_нс': time.perf_counter_ns() - начало_сессии,
        }
        байты = json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2).encode('utf-8') + b'\n'
        with выход.open('xb') as файл:
            файл.write(байты)
            файл.flush()
        print(json.dumps({'схема': данные['схема'], 'профиль': str(выход.relative_to(корень)),
                          'медиана_нс': данные['длительность_нс']['медиана'],
                          'максимум_нс': общий_максимум, 'стадии': сводка,
                          'решение_по_оптимизации': решение}, ensure_ascii=False, sort_keys=True))
    finally:
        фикстура.doCleanups()


if __name__ == '__main__':
    main()

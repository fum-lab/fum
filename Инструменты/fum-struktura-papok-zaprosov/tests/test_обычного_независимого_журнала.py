СЦЕНАРИИ = Path(__file__).resolve().parents[1] / 'scripts'
sys.path.insert(0, str(СЦЕНАРИИ))
import независимый_журнал as журнал

ПИСАТЕЛЬ = '00000000-0000-0000-0000-000000000003'
ПИСАТЕЛИ = (ПИСАТЕЛЬ, '00000000-0000-0000-0000-000000000004')
ЭТАПЫ = ('2026-06-24_12-00-00_MSK_создать-первый-этап',
         '2026-06-25_12-00-00_MSK_создать-второй-этап')


class НезависимыйОбычныйЖурнал(unittest.TestCase):
    def основа(сам, фикс):
        for запрос in (фикс.root / 'Журнал').glob('*/запрос.md'):
            запрос.chmod(0o644)
            отчёт = запрос.with_name('отчёт.md')
            if not отчёт.exists():
                фикс.write(отчёт.relative_to(фикс.root).as_posix(), '# Отчёт\n\n[Запрос](запрос.md).\n')
            отчёт.chmod(0o644)
        фикс.commit()
        return фикс.git('rev-parse', 'HEAD').stdout.strip()

    def план(сам, фикс, база, номер=0, команды=None):
        этап = ЭТАПЫ[номер]
        название = ('Создать первый этап', 'Создать второй этап')[номер]
        основание = {'коммит': база, 'путь': 'Журнал/README.md',
            'sha256': hashlib.sha256((фикс.root / 'Журнал/README.md').read_bytes()).hexdigest()}
        return журнал.подготовить_пару(фикс.root, этап, этап.split('_MSK_', 1)[1],
            название, прежний.THREAD_ID, ['Повтор.\n', 'Повтор.\n'] if команды is None else команды,
            писатель=ПИСАТЕЛИ[номер], основание=основание)

    def установить(сам, фикс, план):
        with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': план[1]['писатель']}):
            журнал.установить_пару(фикс.root, *план)

    def test_чистый_план_и_точная_установка_сохраняют_соседей(сам):
        with репозиторий() as фикс:
            база = сам.основа(фикс)
            до = снимок(фикс.root)
            план = сам.план(фикс, база)
            сам.assertEqual(до, снимок(фикс.root))
            сам.assertEqual(2, len(план[0]))
            сам.установить(фикс, план)
            for имя, данные in до.items():
                if isinstance(данные[0], bytes):
                    сам.assertEqual(данные[0], (фикс.root / имя).read_bytes(), имя)
                    сам.assertEqual(данные[1], stat.S_IMODE((фикс.root / имя).stat().st_mode), имя)
            запрос = (фикс.root / 'Журнал' / ЭТАПЫ[0] / 'запрос.md').read_text()
            сам.assertEqual(2, запрос.count('Повтор.\n'))
            сам.assertNotIn('отложен до передачи', запрос)
            до_повтора = снимок(фикс.root)
            сам.установить(фикс, план)
            сам.assertEqual(до_повтора, снимок(фикс.root))

    def test_две_ветки_из_одной_базы_и_merge_сохраняют_прежние_карточки(сам):
        with репозиторий() as фикс, tempfile.TemporaryDirectory() as место:
            база = сам.основа(фикс)
            старые = {п.relative_to(фикс.root).as_posix(): п.read_bytes()
                for п in (фикс.root / 'Журнал').rglob('*.md')}
            головы = []
            для_слияния = []
            for н in range(2):
                корень = Path(место) / str(н)
                фикс.git('worktree', 'add', '-b', 'этап-' + str(н), str(корень), база)
                дерево = SimpleNamespace(root=корень)
                план = сам.план(дерево, база, н)
                сам.установить(дерево, план)
                subprocess.run(['git', '-C', str(корень), 'add', '--all'], check=True, capture_output=True)
                subprocess.run(['git', '-C', str(корень), 'commit', '-qm', 'этап'], check=True, capture_output=True)
                голова = фикс.git('rev-parse', 'этап-' + str(н)).stdout.strip()
                головы.append(голова)
                сам.assertEqual([база], фикс.git('show', '-s', '--format=%P', голова).stdout.split())
                для_слияния.append(план[1]['писатель'])
                фикс.git('worktree', 'remove', str(корень))
            сам.assertEqual(list(ПИСАТЕЛИ), для_слияния)
            фикс.git('switch', 'этап-0')
            фикс.git('merge', '--no-ff', '--no-edit', 'этап-1')
            сам.assertEqual(головы, фикс.git('show', '-s', '--format=%P').stdout.split())
            for имя, данные in старые.items():
                сам.assertEqual(данные, (фикс.root / имя).read_bytes(), имя)
            голова = фикс.git('rev-parse', 'HEAD').stdout.strip()
            состав = журнал.состав_принятого_дерева(фикс.root, голова)
            индекс = журнал.построить_принятый_индекс(фикс.root, состав)
            перестановка = copy.deepcopy(состав)
            перестановка['записи'].reverse()
            сам.assertEqual(индекс['байты'], журнал.построить_принятый_индекс(фикс.root, перестановка)['байты'])
            сам.assertEqual(4, индекс['записей'])
            ожидаемые = {'Журнал/' + папка + '/' + часть
                for папка in (прежний.EARLY, прежний.LATE, *ЭТАПЫ)
                for часть in ('запрос.md', 'отчёт.md')}
            сам.assertEqual(ожидаемые, {ф['путь'] for з in состав['записи'] for ф in з['файлы']})
            строки = индекс['байты'].decode()
            сам.assertLess(строки.index('Создать первый этап'), строки.index('Создать второй этап'))

    def test_пропуск_дубль_подмена_и_неизвестная_версия_закрывают_полный_состав(сам):
        with репозиторий() as фикс:
            база = сам.основа(фикс)
            состав = журнал.состав_принятого_дерева(фикс.root, база)
            журнал.построить_принятый_индекс(фикс.root, состав)
            for вид in ('пропуск', 'дубль', 'версия', 'sha', 'режим', 'приёмка'):
                изменённый = copy.deepcopy(состав)
                if вид == 'пропуск': изменённый['записи'].pop()
                if вид == 'дубль': изменённый['записи'].append(copy.deepcopy(изменённый['записи'][0]))
                if вид == 'версия': изменённый['записи'][0]['формат'] = 'неизвестный.99'
                if вид == 'sha': изменённый['записи'][0]['файлы'][0]['sha256'] = '0' * 64
                if вид == 'режим': изменённый['записи'][0]['файлы'][0]['режим'] = 0o600
                if вид == 'приёмка': изменённый['записи'][0]['приёмка']['sha256'] = '0' * 64
                with сам.subTest(вид=вид), сам.assertRaises(ValueError):
                    журнал.построить_принятый_индекс(фикс.root, изменённый)

    def test_подмена_плана_или_писателя_отказывает_до_установки(сам):
        with репозиторий() as фикс:
            база = сам.основа(фикс)
            файлы, план = сам.план(фикс, база)
            до = снимок(фикс.root)
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': прежний.THREAD_ID}), сам.assertRaises(ValueError):
                журнал.установить_пару(фикс.root, файлы, план)
            изменённый = copy.deepcopy(план)
            изменённый['этап'] = '0' * 64
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ПИСАТЕЛЬ}), сам.assertRaises(ValueError):
                журнал.установить_пару(фикс.root, файлы, изменённый)
            сам.assertEqual(до, снимок(фикс.root))

    def test_чужая_открытая_пара_и_устаревший_индекс_не_дают_допуска(сам):
        with репозиторий() as фикс:
            база = сам.основа(фикс)
            состав = журнал.состав_принятого_дерева(фикс.root, база)
            индекс = журнал.построить_принятый_индекс(фикс.root, состав)
            фикс.write('Индексы/навигация-журнала.md', индекс['байты'])
            план = сам.план(фикс, база)
            сам.установить(фикс, план)
            журнал.проверить_смешанный(фикс.root, состав, открытая=план[1])
            (фикс.root / 'Индексы/навигация-журнала.md').write_bytes(индекс['байты'] + b'\n')
            with сам.assertRaises(ValueError): журнал.проверить_смешанный(фикс.root, состав, открытая=план[1])
            (фикс.root / 'Индексы/навигация-журнала.md').write_bytes(индекс['байты'])
            журнал.проверить_смешанный(фикс.root, состав, открытая=план[1])
            with сам.assertRaises(ValueError): журнал.проверить_смешанный(фикс.root, состав)
            сам.установить(фикс, сам.план(фикс, база, 1))
            with сам.assertRaises(ValueError): журнал.проверить_смешанный(фикс.root, состав, открытая=план[1])

    def test_смена_поколения_отказывает_с_корректным_прежним_индексом(сам):
        with репозиторий() as фикс:
            база = сам.основа(фикс)
            прежний_состав = журнал.состав_принятого_дерева(фикс.root, база)
            прежний_индекс = журнал.построить_принятый_индекс(фикс.root, прежний_состав)
            сам.установить(фикс, сам.план(фикс, база))
            фикс.commit()
            новый = журнал.состав_принятого_дерева(фикс.root, фикс.git('rev-parse', 'HEAD').stdout.strip())
            фикс.write('Индексы/навигация-журнала.md', прежний_индекс['байты'])
            with сам.assertRaisesRegex(ValueError, 'устаревший смешанный индекс'):
                журнал.проверить_смешанный(фикс.root, новый)
            фикс.write('Индексы/навигация-журнала.md', журнал.построить_принятый_индекс(фикс.root, новый)['байты'])
            журнал.проверить_смешанный(фикс.root, новый)


    def test_префиксные_имена_сортируются_по_папкам_а_не_полным_путям(сам):
        with репозиторий() as фикс:
            база = сам.основа(фикс)
            имена = ('2026-06-24_12-00-00_MSK_создать-этап',
                '2026-06-24_12-00-00_MSK_создать-этап-продолжение')
            основание = {'коммит': база, 'путь': 'Журнал/README.md',
                'sha256': hashlib.sha256((фикс.root / 'Журнал/README.md').read_bytes()).hexdigest()}
            for н, имя in enumerate(имена):
                метка = имя.split('_MSK_', 1)[1]
                план = журнал.подготовить_пару(фикс.root, имя, метка, метка.replace('-', ' ').capitalize(),
                    прежний.THREAD_ID, ['Точная команда.\n'], писатель=ПИСАТЕЛИ[н], основание=основание)
                сам.установить(фикс, план)
            фикс.commit()
            состав = журнал.состав_принятого_дерева(фикс.root, фикс.git('rev-parse', 'HEAD').stdout.strip())
            журнал.построить_принятый_индекс(фикс.root, состав)
            сам.assertEqual(sorted(з['журнал'] for з in состав['записи']), [з['журнал'] for з in состав['записи']])

    def test_защищённый_ресурс_не_подменяется_новой_парой(сам):
        with репозиторий() as фикс:
            база = сам.основа(фикс)
            план = сам.план(фикс, база)
            до = снимок(фикс.root)
            исходное_чтение = Path.read_bytes
            защищённый = Path(журнал.каркас.__file__)
            def читать(путь):
                данные = исходное_чтение(путь)
                return данные + b'\n' if путь == защищённый else данные
            with mock.patch.object(Path, 'read_bytes', читать):
                with сам.assertRaisesRegex(ValueError, 'закреплённый ресурс P.1'):
                    сам.план(фикс, база)
                with сам.assertRaisesRegex(ValueError, 'закреплённый ресурс P.1'):
                    сам.установить(фикс, план)
            сам.assertEqual(до, снимок(фикс.root))


#!/usr/bin/env python3
"""Повторяемый профиль на открытой фикстуре; вывод JSON направляется вне Git."""

import argparse
import hashlib
import json
from pathlib import Path
import platform
import resource
import statistics
import subprocess
import sys
import time

from test_расширение_шаблонов import ПроверкиРасширения, ОПИСАНИЕ, ДАННЫЕ, ОЖИДАЕМЫЙ, КОРЕНЬ


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--повторы', type=int, default=10)
    параметры = разбор.parse_args()
    if not 2 <= параметры.повторы <= 100:
        разбор.error('число повторов должно быть от 2 до 100')
    запуски = []
    начало = time.perf_counter_ns()
    for номер in range(параметры.повторы):
        пример = ПроверкиРасширения()
        пример.setUp()
        модуль = пример.модуль
        наблюдение = модуль.Наблюдение()
        try:
            план = модуль.план_расширения(пример.корень, ОПИСАНИЕ, наблюдение)
            модуль.применить_план(пример.корень, план, наблюдение)
            повтор = модуль.применить_план(пример.корень, план, наблюдение)
            assert повтор['повтор']
            документ = модуль.план_документа(пример.корень, ДАННЫЕ, наблюдение)
            модуль.применить_план(пример.корень, документ, наблюдение)
            assert (пример.корень / ДАННЫЕ['путь']).read_text() == ОЖИДАЕМЫЙ
            try:
                модуль.план_расширения(пример.корень, {}, наблюдение)
            except модуль.ОшибкаРасширения:
                pass
            else:
                raise AssertionError('повреждённый вход принят')
            запуски.append({'повтор': номер + 1, 'первый_в_процессе': номер == 0,
                           'этапы': наблюдение.записи})
        finally:
            пример.doCleanups()
    сводка = {}
    for этап in ('план расширения', 'план документа', 'применение'):
        длительности = [з['длительность_нс'] for п in запуски for з in п['этапы']
                        if з['этап'] == этап and з['исход'] == 'успех']
        сводка[этап] = {'измерений': len(длительности), 'медиана_нс': statistics.median(длительности),
                       'максимум_нс': max(длительности)}
    версия = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=КОРЕНЬ, text=True).strip()
    исходники = {имя: hashlib.sha256(байты).hexdigest() for имя, байты in модуль.ИСПОЛНЯЕМЫЕ_БАЙТЫ.items()}
    исходники['tests/test_расширение_шаблонов.py'] = hashlib.sha256(Path(__file__).with_name('test_расширение_шаблонов.py').read_bytes()).hexdigest()
    исходники['tests/профиль_расширения.py'] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    вывод = {'схема': 'fum.профиль-расширения-шаблонов.1', 'HEAD': версия,
        'источник': 'незакоммиченная реализация; точные хэши ниже', 'исходники': исходники,
        'Python': platform.python_version(), 'система': platform.system(),
        'архитектура': platform.machine(), 'повторов': параметры.повторы,
        'кэш': 'новая файловая фикстура на повтор; первый импорт холодный, остальные тёплые; кэш ОС не сбрасывается',
        'вход_sha256': hashlib.sha256(модуль.сериализовать(ОПИСАНИЕ).encode()).hexdigest(),
        'критерий': 'если максимум успешной операции < 100 мс на этой малой фикстуре, алгоритм не оптимизировать',
        'календарная_длительность_нс': time.perf_counter_ns() - начало,
        'RSS_пик_процесса': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
        'RSS_единица': 'байт' if sys.platform == 'darwin' else 'КиБ',
        'RSS_граница': 'пик процесса за всю жизнь, включая фикстуры; не сумма пиков этапов',
        'I/O': 'unknown: счётчик не подключён', 'накладные_расходы': 'unknown: отдельное измерение отсутствует',
        'сводка': сводка, 'запуски': запуски}
    print(json.dumps(вывод, ensure_ascii=False, sort_keys=True, indent=2))


if __name__ == '__main__':
    главная()

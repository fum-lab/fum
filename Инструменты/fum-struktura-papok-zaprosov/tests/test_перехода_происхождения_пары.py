@unittest.skipIf(ИСПЫТАТЬ_ПРЕЖНИЙ, 'RED ограничен тремя фактическими границами прежнего producer')
class ПроверкиПерехода(unittest.TestCase):
    def setUp(сам):
        сам.ф = ФикстураПары(); сам.addCleanup(сам.ф.закрыть)

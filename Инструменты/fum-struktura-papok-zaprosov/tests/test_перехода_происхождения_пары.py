    def план(сам, вход=None, выбор=None, акт=None):
        return сам.м.построить_план(вход or сам.ф.вход(),
            выбранное_поручение=акт or сам.фикс.выбор,
            выбранный_переход=выбор or сам.ф.выбор())

    def применить(сам, план):
        return сам.м.применить_план(сам.ф.вход(), план, ожидаемый_хэш=хэш(канон(план)),
            выбранное_поручение=сам.фикс.выбор, выбранный_переход=сам.ф.выбор())

    def снимок(сам):
        # Включает Git index/refs/config, выбранные источники и immutable план.
        результат = {}
        for п in Path(сам.ф.прежняя.каталог.name).resolve().rglob('*'):
            if п.is_symlink():
                с = п.lstat(); результат[str(п)] = (os.readlink(п), с.st_mode, с.st_ino, с.st_mtime_ns)
            elif п.is_file():
                с = п.stat(); результат[str(п)] = (п.read_bytes(), с.st_mode, с.st_ino, с.st_mtime_ns)
        return результат

    def отказ_без_эффектов(сам, действие):
        до = сам.снимок()
        with сам.assertRaises((ValueError, OSError, RuntimeError)): действие()
        сам.assertEqual(до, сам.снимок())

    def test_три_оригинала_буквальная_форма_и_поручение_пары_сохраняют_внешние_разделы(сам):
        до = сам.снимок(); план = сам.план()
        сам.assertEqual(до, сам.снимок())
        сам.assertEqual([з['текст'] for з in план['команды']], сам.тексты)
        сам.assertEqual(сам.применить(план)['записано'], 2)
        после = сам.снимок()
        сам.assertEqual(set(до), set(после))
        сам.assertEqual({п for п in до if до[п] != после[п]},
            {str(сам.фикс.корень / з['путь']) for з in план['выходы']})
        for прежний, выход in zip(план['прежние'], план['выходы'], strict=True):
            данные = base64.b64decode(прежний)
            новый = (сам.фикс.корень / выход['путь']).read_bytes()
            if выход['путь'].endswith('запрос.md'):
                а, б = сам.м.рендер._секции(данные, сам.м.рендер.РАЗДЕЛЫ_ЗАПРОСА)[0]['Текст запроса']
                в, г = сам.м.рендер._секции(новый, сам.м.рендер.РАЗДЕЛЫ_ЗАПРОСА)[0]['Текст запроса']
                сам.assertEqual((данные[:а], данные[б:]), (новый[:в], новый[г:]))
        событие = сам.м.блоки.прочитать_журнал((сам.фикс.корень / сам.фикс.журнал / 'отчёт.md').read_bytes())[0]
        сам.assertEqual(событие['текст'], сам.фикс.поручение)
        сам.assertEqual(событие['источник'], {'задача': сам.фикс.исполнитель, **сам.ф.выбор()['поручение']['позиция']})


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def канон(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True,
                      separators=(',', ':'), allow_nan=False).encode()


class ФикстураПары:
    """Переиспользуется принятая Git/native фикстура; production её не импортирует."""
    def __init__(сам):
        сам.прежняя = прежние.ПроверкиПроисхождения('runTest')
        сам.прежняя.setUp()
        сам.фикс = сам.прежняя.фикс
        сам.старый_выбор = сам.прежняя.выбранный_переход
        сам.форма = 'маркированная'

    def закрыть(сам):
        сам.прежняя.doCleanups()

    def люди(сам, тексты):
        источник = Path(сам.старый_выбор['источники'][0]['путь'])
        записи = [{'type': 'session_meta', 'payload': {'id': сам.фикс.координатор}}]
        for номер, текст in enumerate(тексты):
            записи.append({'timestamp': f'2026-10-14T09:00:{номер:02d}Z',
                'type': 'response_item', 'payload': {'type': 'message', 'role': 'user',
                    'content': [{'type': 'input_text', 'text': текст}],
                    'internal_chat_message_metadata_passthrough': {'content_item_kinds': ['user.text']}}})
        источник.write_bytes(b''.join(канон(з) + b'\n' for з in записи))
        снимок = сам.прежняя.подготовка.коммит.сообщения.прочитать_сообщения(
            источник, сам.фикс.координатор, корень_репозитория=сам.фикс.корень, без_записи=True)
        сам.старый_выбор['источники'] = [{'путь': str(источник),
            'задача': сам.фикс.координатор,
            'экземпляры': [з['экземпляр'] for з in снимок['сообщения']],
            'граница_снимка': {'граница': снимок['граница'], 'sha256': снимок['sha256'],
                'неоднозначные_экземпляры': []}}]
        return снимок

    def прежняя_форма(сам, форма):
        сам.форма = форма
        каркас = прежние.журнал.каркас
        основа = Path(сам.фикс.журнал).name
        метка = каркас.SESSION_PATTERN.fullmatch(основа).group('label')
        заголовок = каркас._заголовок_из_метки(метка)
        текст = сам.фикс.поручение
        if форма == 'маркированная':
            текст = 'Первоначальное агентское поручение ROOT (не сообщение человека):\n\n' + текст
        _, запрос, _ = каркас._каркас_начала(сам.фикс.корень, основа, метка,
            заголовок, сам.фикс.координатор, [текст])
        сам.фикс.записать((Path(сам.фикс.журнал) / 'запрос.md').as_posix(), каркас._request_document(
            основа, заголовок, None, None, [текст], сам.фикс.координатор, {}, запрос).encode())
        сам.старый_выбор['до'] = [{'путь': сам.фикс.журнал + '/' + имя, 'режим': 0o644,
            'sha256': хэш((сам.фикс.корень / сам.фикс.журнал / имя).read_bytes())}
            for имя in ('запрос.md', 'отчёт.md')]

    def только_пара(сам):
        фикс = сам.фикс
        фикс.акт['область'] = [фикс.журнал + '/']
        фикс.записать(фикс.путь_акта, канон(фикс.акт))
        фикс.гит('add', '--', фикс.путь_акта)
        фикс.гит('commit', '-qm', 'Выбрать только собственную пару фикстуры')
        фикс.выбор.update(коммит=фикс.гит('rev-parse', 'HEAD').decode().strip(),
                         sha256=хэш(канон(фикс.акт)))
        фикс.вход['основа'] = {'коммит': фикс.выбор['коммит'],
            'дерево': фикс.гит('rev-parse', 'HEAD^{tree}').decode().strip()}
        фикс.выбранная_основа['основа'] = фикс.вход['основа']

    def вход(сам):
        return {**{к: з for к, з in сам.фикс.вход.items() if к != 'принятый_журнал'},
            'схема': 'fum.вход-перехода-происхождения-пары.1'}

    def выбор(сам):
        байты = сам.фикс.нативный.read_bytes()
        строки = байты.splitlines(keepends=True)
        начало = sum(map(len, строки[:-1]))
        return {**сам.старый_выбор, 'схема': 'fum.выбор-перехода-происхождения-пары.1',
            'форма': сам.форма, 'поручение': {'источник': str(сам.фикс.нативный),
                'позиция': {'начало': начало, 'конец': len(байты), 'sha256': хэш(строки[-1])},
                'префикс': {'граница': len(байты), 'sha256': хэш(байты)},
                'текст_sha256': хэш(сам.фикс.поручение.encode())}}

    def план(сам, *, прежний=False):
        if прежний:
            return сам.прежняя.переход()
        модуль = importlib.import_module('переход_происхождения_пары')
        return модуль.построить_план(сам.вход(), выбранное_поручение=сам.фикс.выбор,
                                   выбранный_переход=сам.выбор())



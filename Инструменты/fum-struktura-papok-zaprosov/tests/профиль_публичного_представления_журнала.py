"""Три свежих процесса первого наблюдения и замыкание исполняемых исходников."""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import statistics
import subprocess
import sys
import time
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_публичного_представления_журнала as проверка


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def инвентарь_исходников():
    имена = subprocess.check_output(['git', '--no-optional-locks', '-C', str(проверка.КОРЕНЬ),
        'ls-files', '-z', '--', '*.py']).decode().split('\0')
    результат = {}
    for имя in имена:
        if not имя or имя.startswith('Proyekcii/'):
            continue
        путь = проверка.КОРЕНЬ / имя
        if путь != путь.resolve() or not путь.is_file():
            raise ValueError('Исходник профиля отсутствует либо перенаправлен')
        результат[имя] = хэш(путь.read_bytes())
    return результат


def исходники_процесса():
    результат = {}
    for модуль in list(sys.modules.values()):
        имя = getattr(модуль, '__file__', None)
        if not имя or not имя.endswith('.py'):
            continue
        путь = Path(имя).resolve()
        if путь.is_relative_to(проверка.КОРЕНЬ):
            результат[путь.relative_to(проверка.КОРЕНЬ).as_posix()] = хэш(путь.read_bytes())
    return результат


def измерить_раунд(номер):
    владелец = unittest.TestCase()
    try:
        ф = проверка.открытый_этап(владелец, наблюдение=True)
        публичные = проверка.importlib.import_module('публичное_представление_событий')
        начало = time.perf_counter_ns()
        for _ in range(100):
            построенное = публичные.сформировать(ф.события[0], ф.замены)
            if not публичные.проверить_повтор(построенное, ф.события[0]):
                raise ValueError('Не подтверждён построитель профиля')
        построение = (time.perf_counter_ns() - начало) // 100
        планирование = {}
        план = проверка.свежий_процесс(ф.корень, 'переход_публичного_журнала', 'подготовить', ф.вход_перехода, профиль=планирование)
        применение = {}
        проверка.свежий_процесс(ф.корень, 'переход_публичного_журнала', 'применить', ф.вход_перехода, план, профиль=применение)
        до = проверка.снимок_повтора(ф)
        повтор = проверка.свежий_процесс(ф.корень, 'переход_публичного_журнала', 'применить', ф.вход_перехода, план)
        проверка.свежий_процесс(ф.корень, 'переход_публичного_журнала', 'проверить', ф.вход_перехода, план)
        if not повтор['повтор'] or до != проверка.снимок_повтора(ф):
            raise ValueError('Повтор изменил файлы, их метаданные, индекс или refs')
        повтор_оригинала = copy.deepcopy(ф.fill)
        повтор_оригинала['разрешение'] = ф.вход_перехода['разрешение']
        начало = time.perf_counter_ns()
        план_повтора = проверка.свежий_процесс(ф.корень, 'наполнение_карточки', 'подготовить', повтор_оригинала)
        проверка.свежий_процесс(ф.корень, 'наполнение_карточки', 'применить', повтор_оригинала, план_повтора)
        наполнение = time.perf_counter_ns() - начало
        if ф.блоки.прочитать_журнал(ф.отчёт.read_bytes()) != [построенное]:
            raise ValueError('RAW replay изменил первое наблюдение')
        исходники = dict(план['зависимости']['код'])
        for имя, SHA in план['зависимости']['код_допуска'].items():
            if имя in исходники and исходники[имя] != SHA:
                raise ValueError('Расходятся загруженные версии исходника')
            исходники[имя] = SHA
        результат = {'номер': номер, 'процесс': os.getpid(), 'вход_sha256': хэш(json.dumps(
            ф.вход_перехода, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()),
            'исходный_отчёт_sha256': ф.вход_перехода['исходный_отчёт_sha256'],
            'native_sha256': ф.вход_перехода['события'][0]['native']['sha256'],
            'исполняемые_исходники': исходники, 'повтор_без_эффектов': True,
            'стадии_нс': {'построение_и_проверка': построение, 'планирование': планирование['планирование_нс'],
                'сохранение_оригинала': применение['сохранение_оригинала_нс'],
                'установка': применение['установка_нс'], 'последующее_наполнение': наполнение}}
    finally:
        владелец.doCleanups()
    результат['исходники_процесса'] = исходники_процесса()
    return результат


def измерить():
    до = инвентарь_исходников()
    результаты = []
    for номер in range(1, 4):
        процесс = subprocess.run([sys.executable, '-I', '-S', '-B', str(Path(__file__).resolve()),
            '--измерить-раунд', str(номер)], cwd=проверка.КОРЕНЬ,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=300)
        if процесс.returncode:
            raise ValueError('Свежий процесс профиля отказал: ' + процесс.stderr.decode())
        результаты.append(json.loads(процесс.stdout))
    после = инвентарь_исходников()
    if до != после or len({п['процесс'] for п in результаты}) != 3:
        raise ValueError('Дрейф исходников либо повтор PID профиля')
    замыкание = set()
    for раунд in результаты:
        for поле in ('исполняемые_исходники', 'исходники_процесса'):
            for имя, SHA in раунд[поле].items():
                if до.get(имя) != SHA:
                    raise ValueError('Исполненный исходник не совпал с предварительным инвентарём: ' + имя)
                замыкание.add(имя)
    медианы = {имя: int(statistics.median(п['стадии_нс'][имя] for п in результаты)) for имя in результаты[0]['стадии_нс']}
    база = subprocess.check_output(['git', '--no-optional-locks', '-C', str(проверка.КОРЕНЬ), 'rev-parse', 'HEAD']).decode().strip()
    return {'схема': 'fum.профиль-публичного-журнала.2', 'база': база,
        'исходники_до': {имя: до[имя] for имя in sorted(замыкание)},
        'исходники_после': {имя: после[имя] for имя in sorted(замыкание)},
        'раунды': результаты, 'медианы_нс': медианы, 'версия_интерпретатора': sys.version,
        'граница': 'Три отдельных -I -S -B worker-процесса, каждый с собственной открытой Git-фикстурой .2. До запуска и после всей серии проверен полный канонический tracked Python-инвентарь; замыкание включает фактически исполненные модули перехода/guard и fixture/helpers/profile. Подготовка фикстуры, внешняя инвентаризация, отдельный повтор и сохранение JSON исключены из таймеров стадий. Планирование включает внутренние guard, импорт и сверки исходников; последующее наполнение измеряет два полных свежих subprocess, включая их запуск, импорт и проверки. Кэш ОС не очищается. Вложенные интервалы и стадии не суммируются. Фикстура не является native production переходом, ROOT9, интеграцией или state2.',
        'решение': 'Сохранить точные замены и полные повторные сверки. Отдельный guard, проверка первого поручения и долговечное сохранение необходимы по контракту; эти измерения не обосновывают их удаление и не доказывают ускорения всего допуска.'}


def главная():
    разбор = argparse.ArgumentParser(allow_abbrev=False)
    выбор = разбор.add_mutually_exclusive_group(required=True)
    выбор.add_argument('--выход')
    выбор.add_argument('--измерить-раунд', type=int, choices=(1, 2, 3))
    аргументы = разбор.parse_args()
    if аргументы.измерить_раунд is not None:
        print(json.dumps(измерить_раунд(аргументы.измерить_раунд), ensure_ascii=False, sort_keys=True))
        return
    выход = Path(аргументы.выход)
    if выход.exists() or not выход.is_absolute() or выход != выход.resolve() or not выход.parent.is_dir():
        raise ValueError('Нужен новый физический адрес профиля')
    данные = измерить()
    дескриптор = os.open(выход, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'wb') as поток:
        поток.write((json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode())
        поток.flush()
        os.fsync(поток.fileno())
    print(json.dumps({'схема': данные['схема'], 'процессы': [п['процесс'] for п in данные['раунды']],
        'медианы_нс': данные['медианы_нс'], 'sha256': хэш(выход.read_bytes())}, ensure_ascii=False, sort_keys=True))


if __name__ == '__main__':
    главная()

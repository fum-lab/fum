"""Раздельный профиль реального публичного перехода на открытых Git-фикстурах."""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import statistics
import subprocess
import time
import unittest

import test_публичного_представления_журнала as проверка


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def измерить():
    результаты = []
    for номер in range(3):
        владелец = unittest.TestCase()
        try:
            ф = проверка.открытый_этап(владелец)
            публичные = проверка.importlib.import_module('публичное_представление_событий')
            начало = time.perf_counter_ns()
            for _ in range(100):
                построенные = [публичные.сформировать(с, ф.замены) for с in ф.события[:2]]
                if not all(публичные.проверить_повтор(п, с) for п, с in zip(построенные, ф.события)):
                    raise ValueError('Не подтверждён построитель профиля')
            построение = (time.perf_counter_ns() - начало) // 100
            планирование = {}
            план = проверка.свежий_процесс(ф.корень, 'переход_публичного_журнала', 'подготовить', ф.вход_перехода, профиль=планирование)
            применение = {}
            проверка.свежий_процесс(ф.корень, 'переход_публичного_журнала', 'применить', ф.вход_перехода, план, профиль=применение)
            проверка.свежий_процесс(ф.корень, 'переход_публичного_журнала', 'проверить', ф.вход_перехода, план)
            replay = copy.deepcopy(ф.fill)
            replay['разрешение'] = ф.вход_перехода['разрешение']
            начало = time.perf_counter_ns()
            план_replay = проверка.свежий_процесс(ф.корень, 'наполнение_карточки', 'подготовить', replay)
            проверка.свежий_процесс(ф.корень, 'наполнение_карточки', 'применить', replay, план_replay)
            наполнение = time.perf_counter_ns() - начало
            if ф.блоки.прочитать_журнал(ф.отчёт.read_bytes()) != [*построенные, ф.события[2]]:
                raise ValueError('RAW replay изменил публичный журнал')
            результаты.append({'номер': номер + 1, 'вход_sha256': хэш(json.dumps(
                ф.вход_перехода, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()),
                'исходный_отчёт_sha256': ф.вход_перехода['исходный_отчёт_sha256'],
                'native_sha256': ф.вход_перехода['события'][0]['native']['sha256'],
                'код': план['зависимости']['код'], 'код_допуска': план['зависимости']['код_допуска'],
                'стадии_нс': {'построение_и_проверка': построение, 'планирование': планирование['планирование_нс'],
                    'сохранение_оригинала': применение['сохранение_оригинала_нс'],
                    'установка': применение['установка_нс'], 'последующее_наполнение': наполнение}})
        finally:
            владелец.doCleanups()
    медианы = {имя: int(statistics.median(п['стадии_нс'][имя] for п in результаты)) for имя in результаты[0]['стадии_нс']}
    исходники = {п.relative_to(проверка.КОРЕНЬ).as_posix(): хэш(п.read_bytes()) for п in
        (Path(__file__).resolve(), Path(проверка.__file__).resolve())}
    база = subprocess.check_output(['git', '-C', str(проверка.КОРЕНЬ), 'rev-parse', 'HEAD']).decode().strip()
    return {'схема': 'fum.профиль-публичного-журнала.1', 'база': база, 'исходники': исходники,
        'раунды': результаты, 'медианы_нс': медианы,
        'граница': 'Подготовка трёх временных Git-фикстур исключена. Построение включает независимую проверку двух событий; остальные стадии измерены раздельно. Планирование/сохранение/установка — внутренние неперекрывающиеся таймеры API; RAW fill включает два свежих процесса. Вложенные интервалы и стадии не суммируются.',
        'решение': 'Сохранить алгоритм точных замен и полные повторные сверки. Изолированный guard и чтение состояния обязательны; профиль не доказывает ускорения всего допуска. Отдельная оптимизация потребует сравнения эквивалентных реализаций.'}


def главная():
    разбор = argparse.ArgumentParser(allow_abbrev=False)
    разбор.add_argument('--выход', required=True)
    аргументы = разбор.parse_args()
    выход = Path(аргументы.выход)
    if выход.exists() or not выход.is_absolute() or выход != выход.resolve() or not выход.parent.is_dir():
        raise ValueError('Нужен новый физический адрес профиля')
    данные = измерить()
    дескриптор = os.open(выход, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'wb') as поток:
        поток.write((json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode())
        поток.flush()
        os.fsync(поток.fileno())
    print(json.dumps({'схема': данные['схема'], 'медианы_нс': данные['медианы_нс'], 'sha256': хэш(выход.read_bytes())}, ensure_ascii=False, sort_keys=True))


if __name__ == '__main__':
    главная()

"""Установка S.2 из двух источников кодом, отдельно принятым из правой ветки."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import unittest
from unittest.mock import patch

import test_установки_принятого_состава_журнала as база


class УстановкаДвухИсточников(unittest.TestCase):
    def setUp(сам):
        маска = os.umask(0o022)
        сам.addCleanup(os.umask, маска)
        среда = patch.dict(os.environ, {'CODEX_THREAD_ID': '00000000-0000-0000-0000-000000000001'})
        среда.start(); сам.addCleanup(среда.stop)
        сам.ф = ф = база.Фикстура()
        сам.addCleanup(ф.закрыть)
        гит = ф.основа.git
        ж = ф.модуль.журнал
        # Источники действительно разошлись: K=R не является предком L.
        старшая = next((ф.корень / 'Журнал').glob('*/запрос.md')).parent
        (старшая / 'материалы').mkdir()
        (старшая / 'материалы/левый.raw').write_bytes(b'left\x00raw\n')
        ф.основа.commit()
        сам.левый = гит('rev-parse', 'HEAD').stdout.strip()
        гит('checkout', '-qb', 'codex/правый', ф.код)
        ф.основа.make_canonical_layout()
        основание_коммит = гит('rev-parse', 'HEAD').stdout.strip()
        основание = {'коммит': основание_коммит, 'путь': 'Журнал/README.md',
            'sha256': hashlib.sha256((ф.корень / 'Журнал/README.md').read_bytes()).hexdigest()}
        имя = '2026-10-19_12-00-00_MSK_закрыть-правый-источник'
        файлы, план = ж.подготовить_пару(ф.корень, имя, 'закрыть-правый-источник', 'Закрыть правый источник',
            os.environ['CODEX_THREAD_ID'], ['Проверить два источника.'],
            писатель=os.environ['CODEX_THREAD_ID'], основание=основание)
        ж.установить_пару(ф.корень, файлы, план)
        материалы = ф.корень / 'Журнал' / имя / 'материалы'
        материалы.mkdir(); (материалы / 'правый.raw').write_bytes(b'right\x00raw\n')
        ф.основа.commit()
        сам.правый = гит('rev-parse', 'HEAD').stdout.strip()
        сам.assertEqual(гит('merge-base', '--is-ancestor', сам.правый, сам.левый, check=False).returncode, 1)
        записи = {}
        for к in (сам.левый, сам.правый):
            for з in ж.состав_принятого_дерева(ф.корень, к)['записи']:
                if з['журнал'] in записи:
                    сам.assertEqual({к: в for к, в in з.items() if к != 'приёмка'},
                        {к: в for к, в in записи[з['журнал']].items() if к != 'приёмка'})
                else: записи[з['журнал']] = з
        сам.состав = {'схема': 'fum.принятый-состав-обычного-журнала.2',
            'коммиты': [сам.левый, сам.правый], 'записи': [записи[и] for и in sorted(записи)]}
        файлы_пар = {}
        for к in (сам.левый, сам.правый):
            for имя_файла, содержимое in ж._файлы_коммита(ф.корень, к).items():
                if имя_файла in файлы_пар:
                    сам.assertEqual(файлы_пар[имя_файла], содержимое)
                файлы_пар[имя_файла] = содержимое
        вход_индекса = {'схема': 'fum.состав-независимого-журнала.3', 'записи': сам.состав['записи']}
        навигация = ж.индексы.построить_индекс(вход_индекса, файлы_пар,
            ожидаемый_sha256=ж.контракт.хэш(ж.контракт.канон(вход_индекса)))['байты']
        сам.целевые_байты = {ж.ПУТЬ_СОСТАВА: база.байты(сам.состав), ж.ПУТЬ_ИНДЕКСА: навигация}
        гит('checkout', '-qb', 'codex/носитель-двух')
        ф.основа.write('Планирование/состав-двух.json', база.байты(сам.состав))
        ф.основа.commit()
        носитель = гит('rev-parse', 'HEAD').stdout.strip()
        сам.к = ф.приватный / 'принятый-код'
        гит('worktree', 'add', '--detach', str(сам.к), сам.правый)
        гит('checkout', '-q', 'codex/фикстура')
        гит('merge', '--no-ff', '--no-commit', сам.правый)
        код = {'коммит': сам.правый, 'путь': база.ПУТЬ_УСТАНОВЩИКА,
            'sha256': hashlib.sha256((сам.к / база.ПУТЬ_УСТАНОВЩИКА).read_bytes()).hexdigest()}
        приёмка = {'схема': 'fum.ROOT-приёмка-кода-установщика-слияния.1',
            'координатор': os.environ['CODEX_THREAD_ID'], 'код': код, 'корень_кода': str(сам.к),
            'исходники': {и: hashlib.sha256((сам.к / и).read_bytes()).hexdigest() for и in база.ИСХОДНИКИ}}
        сам.приёмка = приёмка
        сам.выбор = {'схема': 'fum.выбор-установки-состава-журнала.2',
            'координатор': os.environ['CODEX_THREAD_ID'], 'корень': str(ф.корень),
            'ветка': 'refs/heads/codex/фикстура', 'каталог_состояния': str(ф.каталог),
            'код': код, 'корень_кода': str(сам.к),
            'приёмка_кода': база.сохранить(ф.приватный / 'приёмка-K.json', приёмка),
            'источники': [{'коммит': к, 'дерево': гит('rev-parse', к + '^{tree}').stdout.strip()}
                for к in (сам.левый, сам.правый)],
            'состав': {'коммит': носитель, 'путь': 'Планирование/состав-двух.json',
                'sha256': hashlib.sha256(база.байты(сам.состав)).hexdigest()}}
        ф.выбор = база.сохранить(ф.приватный / 'выбор-двух.json', сам.выбор)
        сам.ожидаемые = база.сохранить(ф.приватный / 'ожидаемые.json',
            [база.состояние(ф.корень / и) for и in ф.модуль.ЦЕЛИ])
        сам.путь_плана = ф.приватный / 'план-двух.json'

    def план(сам, *, успех=True):
        ф = сам.ф
        п = subprocess.run([sys.executable, '-B', str(сам.к / база.ПУТЬ_УСТАНОВЩИКА), 'план',
            '--выбор', ф.выбор['путь'], '--хэш-выбора', ф.выбор['sha256'],
            '--план', str(сам.путь_плана), '--ожидаемые', сам.ожидаемые['путь'],
            '--хэш-ожидаемых', сам.ожидаемые['sha256']], cwd=ф.корень, capture_output=True, text=True)
        if успех:
            сам.assertEqual(п.returncode, 0, п.stderr)
            данные = json.loads(сам.путь_плана.read_bytes())
            сам.assertEqual(данные['схема'], 'fum.план-установки-состава-журнала.3')
            return {'путь': str(сам.путь_плана), 'sha256': hashlib.sha256(сам.путь_плана.read_bytes()).hexdigest()}
        сам.assertNotEqual(п.returncode, 0)
        сам.assertFalse(сам.путь_плана.exists())
        return п

    def работать(сам, план, **параметры):
        п = сам.ф.работник(план, корень_кода=str(сам.к), **параметры)
        вывод, ошибка = п.communicate(timeout=30)
        return п, вывод, ошибка

    def проверить_цели(сам):
        for имя, ожидаемые in сам.целевые_байты.items():
            путь = сам.ф.корень / имя
            сам.assertEqual(путь.read_bytes(), ожидаемые, имя)
            сам.assertEqual(путь.lstat().st_mode & 0o777, 0o644, имя)

    def test_код_правого_источника_устанавливает_и_повторяет_без_изменений(сам):
        ф = сам.ф
        до = база.наблюдение(ф.корень)
        план = сам.план()
        сам.assertEqual(база.наблюдение(ф.корень), до)
        история = база.наблюдение(ф.корень / 'Журнал')
        п, вывод, ошибка = сам.работать(план)
        сам.assertEqual(п.returncode, 0, ошибка)
        сам.assertFalse(json.loads(вывод)['результат']['повтор'])
        сам.проверить_цели()
        сам.assertEqual(база.наблюдение(ф.корень / 'Журнал'), история)
        завершение = ф.завершение(п)
        до, состояние = база.наблюдение(ф.корень), база.наблюдение(ф.каталог)
        второй, вывод, ошибка = сам.работать(план, режим='повтор', завершение=завершение)
        сам.assertEqual(второй.returncode, 0, ошибка)
        сам.assertNotEqual(п.pid, второй.pid)
        сам.assertEqual(json.loads(вывод)['результат']['записей'], 0)
        сам.assertEqual(база.наблюдение(ф.корень), до)
        сам.assertEqual(база.наблюдение(ф.каталог), состояние)

    def test_порядок_источников_не_заменяет_HEAD_и_MERGE_HEAD(сам):
        сам.выбор['источники'].reverse()
        сам.ф.выбор = база.сохранить(сам.ф.приватный / 'обратный-выбор.json', сам.выбор)
        до = база.наблюдение(сам.ф.корень)
        сам.план(успех=False)
        сам.assertEqual(база.наблюдение(сам.ф.корень), до)
        сам.assertEqual(list(сам.ф.каталог.iterdir()), [])

    def test_приёмка_другого_K_не_разрешает_план(сам):
        сам.приёмка['код'] = {**сам.приёмка['код'], 'коммит': сам.левый}
        сам.выбор['приёмка_кода'] = база.сохранить(сам.ф.приватный / 'чужая-приёмка.json', сам.приёмка)
        сам.ф.выбор = база.сохранить(сам.ф.приватный / 'выбор-с-чужой-приёмкой.json', сам.выбор)
        до = база.наблюдение(сам.ф.корень)
        сам.план(успех=False)
        сам.assertEqual(база.наблюдение(сам.ф.корень), до)
        сам.assertEqual(list(сам.ф.каталог.iterdir()), [])

    def test_дрейф_родителя_после_плана_отказывает_до_намерения(сам):
        план = сам.план()
        (сам.ф.корень / '.git/MERGE_HEAD').write_text(сам.левый + '\n')
        до = база.наблюдение(сам.ф.корень)
        п, _, ошибка = сам.работать(план)
        сам.assertNotEqual(п.returncode, 0)
        сам.assertIn('дрейф', ошибка)
        сам.assertEqual(база.наблюдение(сам.ф.корень), до)
        сам.assertEqual(list(сам.ф.каталог.iterdir()), [])

    def test_дрейф_закрытого_RAW_отказывает_до_намерения(сам):
        план = сам.план()
        путь = next((сам.ф.корень / 'Журнал').glob('*/материалы/правый.raw'))
        путь.write_bytes(b'changed\n')
        до = база.наблюдение(сам.ф.корень)
        п, _, ошибка = сам.работать(план)
        сам.assertNotEqual(п.returncode, 0)
        сам.assertIn('исторические байты', ошибка)
        сам.assertEqual(база.наблюдение(сам.ф.корень), до)
        сам.assertEqual(list(сам.ф.каталог.iterdir()), [])

    def test_смерть_между_целями_восстанавливается_с_тем_же_выбором(сам):
        план = сам.план()
        история = база.наблюдение(сам.ф.корень / 'Журнал')
        до_второй = база.состояние(сам.ф.корень / сам.ф.модуль.ЦЕЛИ[1])
        п, _, _ = сам.работать(план, точка='после-rename-0')
        сам.assertEqual(п.returncode, 73)
        сам.assertEqual((сам.ф.корень / сам.ф.модуль.ЦЕЛИ[0]).read_bytes(), сам.целевые_байты[сам.ф.модуль.ЦЕЛИ[0]])
        сам.assertEqual(база.состояние(сам.ф.корень / сам.ф.модуль.ЦЕЛИ[1]), до_второй)
        сам.assertEqual(база.наблюдение(сам.ф.корень / 'Журнал'), история)
        остановка = сам.ф.остановка(п, 73)
        новый, _, ошибка = сам.работать(план, режим='восстановить', остановка=остановка)
        сам.assertEqual(новый.returncode, 0, ошибка)
        сам.проверить_цели()
        сам.assertEqual(база.наблюдение(сам.ф.корень / 'Журнал'), история)
        завершение = сам.ф.завершение(новый)
        до = база.наблюдение(сам.ф.корень), база.наблюдение(сам.ф.каталог)
        повтор, _, ошибка = сам.работать(план, режим='повтор', завершение=завершение)
        сам.assertEqual(повтор.returncode, 0, ошибка)
        сам.assertEqual((база.наблюдение(сам.ф.корень), база.наблюдение(сам.ф.каталог)), до)

import json
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from канон import ОшибкаВхода, кодировать, хэш
from диалог import экспортировать
from очередь import Очередь
from test_диалог import ЗАДАЧА, строка_события, сообщение

СНИМОК = '00000000-0000-4000-8000-000000000002'


class ПоздняяОчередь(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name).resolve()
        сам.источник = сам.корень / 'диалог.jsonl'
        сам.начало = строка_события('session_meta', {'id': ЗАДАЧА}) + сообщение('user', 'начать')
        сам.источник.write_bytes(сам.начало)
        _, сам.курсор = экспортировать(сам.начало, ЗАДАЧА)
        сам.решения = []
        сам.очередь = Очередь.создать(сам.корень / 'очередь', сам.источник, ЗАДАЧА, СНИМОК, 'a' * 64, сам.курсор, ['читать', 'писать'])
        сам.привязка = сам.очередь.привязка

    def связь(сам, запрос):
        return {'запрос': запрос, 'состояние': 'доступен', 'решения': сам.решения}

    def дописать(сам, байты):
        with сам.источник.open('ab') as поток: поток.write(байты)

    def решение(сам, доставка, действие='учесть', разрешения=None):
        запись = {'идентификатор': '00000000-0000-4000-8000-000000000003', 'ссылка': доставка['ссылка'], 'действие': действие, 'разрешения': разрешения}
        сам.решения = [запись]
        return запись

    def test_поздние_повторы_и_авария_между_доставкой_и_подтверждением(сам):
        сам.дописать(сообщение('user', 'одинаково') * 2)
        первая = сам.очередь.доставить(сам.связь)
        заново = Очередь(сам.корень / 'очередь', сам.привязка)
        сам.assertEqual(первая, заново.доставить(сам.связь))
        сам.решение(первая)
        заново.подтвердить(первая['ссылка'], сам.связь)
        вторая = заново.доставить(сам.связь)
        сам.assertNotEqual(первая['ссылка'], вторая['ссылка'])
        сам.assertEqual(первая['сырая_строка'], вторая['сырая_строка'])
        сам.assertEqual(вторая, заново.доставить(сам.связь))

    def test_частичный_хвост_завершается_ровно_один_раз(сам):
        хвост = сообщение('user', 'поздно')
        сам.дописать(хвост[:-1])
        сам.assertIsNone(сам.очередь.доставить(сам.связь))
        сам.assertEqual(сам.очередь.барьер(сам.связь)['состояние'], 'неоднозначно')
        сам.дописать(b'\n')
        доставка = сам.очередь.доставить(сам.связь)
        сам.решение(доставка)
        сам.очередь.подтвердить(доставка['ссылка'], сам.связь)
        сам.assertIsNone(сам.очередь.доставить(сам.связь))
        сам.assertIsNotNone(сам.очередь.барьер(сам.связь)['барьер'])

    def test_хук_не_отмена_и_не_основание_человеческого_решения(сам):
        сам.дописать(строка_события('response_item', {'type': 'message', 'role': 'user', 'content': [{'type': 'input_text', 'text': '<hook_prompt hook_run_id="1">остановись</hook_prompt>'}]}))
        доставка = сам.очередь.доставить(сам.связь)
        сам.assertEqual(доставка['происхождение'], 'служебный hook')
        сам.очередь.подтвердить(доставка['ссылка'], сам.связь)
        сам.assertIsNotNone(сам.очередь.барьер(сам.связь)['барьер'])
        сам.решение(доставка, 'отозвать')
        сам.assertEqual(сам.очередь.барьер(сам.связь)['состояние'], 'неоднозначно')

    def test_настоящая_отмена_и_старое_поколение(сам):
        старый = сам.очередь.барьер(сам.связь)['барьер']
        сам.дописать(сообщение('user', 'остановись'))
        доставка = сам.очередь.доставить(сам.связь)
        сам.решение(доставка, 'отозвать')
        итог = сам.очередь.проверить_барьер(старый, сам.связь)
        сам.assertFalse(итог['совпадает'])
        сам.assertEqual(итог['состояние'], 'отменено')
        сам.очередь.подтвердить(доставка['ссылка'], сам.связь)
        сам.assertEqual(сам.очередь.барьер(сам.связь)['состояние'], 'отменено')

    def test_текст_не_определяет_решение_и_подтверждение_не_обрабатывает_человека(сам):
        сам.дописать(сообщение('user', 'остановись'))
        доставка = сам.очередь.доставить(сам.связь)
        with сам.assertRaises(ОшибкаВхода): сам.очередь.подтвердить(доставка['ссылка'], сам.связь)
        сам.assertEqual(сам.очередь.барьер(сам.связь)['состояние'], 'неоднозначно')
        сам.решение(доставка, 'учесть')
        сам.очередь.подтвердить(доставка['ссылка'], сам.связь)
        сам.assertIsNotNone(сам.очередь.барьер(сам.связь)['барьер'])

    def test_потеря_канала_и_отсутствие_свежего_наблюдения(сам):
        старый = сам.очередь.барьер(сам.связь)['барьер']
        новая = Очередь(сам.корень / 'очередь', сам.привязка)
        сам.assertFalse(новая.проверить_барьер(старый, None)['совпадает'])
        сам.источник.unlink()
        сам.assertEqual(новая.барьер(сам.связь)['состояние'], 'канал утрачен')
        сам.источник.write_bytes(сам.начало)
        сам.assertIsNone(новая.барьер(сам.связь)['барьер'])

    def test_подмена_идентификатора_курсора_и_префикса(сам):
        неверная = dict(сам.привязка, снимок=ЗАДАЧА)
        with сам.assertRaises(ОшибкаВхода): Очередь(сам.корень / 'очередь', неверная).состояние()
        сам.источник.write_bytes(сам.начало.replace('начать'.encode(), 'забыть'.encode()))
        сам.assertEqual(сам.очередь.барьер(сам.связь)['состояние'], 'неоднозначно')
        сам.источник.write_bytes(сам.начало)
        сам.assertIsNone(сам.очередь.барьер(сам.связь)['барьер'])

    def test_сужение_не_расширяется_и_не_сбрасывается_подтверждением(сам):
        сам.дописать(сообщение('user', 'только чтение'))
        доставка = сам.очередь.доставить(сам.связь)
        сам.решение(доставка, 'сузить', ['читать'])
        сам.очередь.подтвердить(доставка['ссылка'], сам.связь)
        итог = сам.очередь.барьер(сам.связь)
        сам.assertEqual(итог['разрешения'], ['читать'])
        сам.решения[0] = dict(сам.решения[0], идентификатор='00000000-0000-4000-8000-000000000004', разрешения=['читать', 'писать'])
        сам.assertIsNone(сам.очередь.барьер(сам.связь)['барьер'])

    def test_аварийная_метка_и_оборванный_журнал_не_признаются_успехом(сам):
        старый = сам.очередь.барьер(сам.связь)['барьер']
        with (сам.корень / 'очередь' / 'события.jsonl').open('ab') as поток: поток.write(b'{')
        сам.assertFalse(сам.очередь.проверить_барьер(старый, сам.связь)['совпадает'])


if __name__ == '__main__': unittest.main()

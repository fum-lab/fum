    def test_чужая_квитанция_и_подмена_идентичности(сам):
        параметры = сам.параметры()
        материализация.материализовать(**параметры)
        исходная = сам.квитанция.read_bytes()
        for поле, значение in [('идентификатор_раунда', '00000000-0000-4000-8000-000000000099'), ('хэш_входа', '0'*64), ('дерево_входа', сам.вход['исходный_коммит']), ('лишнее', True)]:
            другая = прочитать(исходная); другая[поле] = значение; сам.квитанция.write_bytes(кодировать(другая))
            with сам.subTest(поле=поле), сам.assertRaises(ОшибкаВхода): материализация.проверить_материализацию(**параметры)
        сам.квитанция.write_bytes(исходная)

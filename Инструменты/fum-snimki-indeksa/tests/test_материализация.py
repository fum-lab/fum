    def test_короткая_запись_и_переполнение_не_дают_квитанцию(сам):
        параметры = сам.параметры()
        настоящий = os.write
        создать_файл = материализация._создать_файл
        for номер, ошибка in enumerate(('short', 'zero', 'full')):
            цель = сам.папка / ('target-' + str(номер)); квитанция = сам.папка / ('receipt-' + str(номер))
            def запись(дескриптор, байты):
                if ошибка == 'full': raise OSError(errno.ENOSPC, 'synthetic full')
                return настоящий(дескриптор, байты[:len(байты)//2]) if ошибка == 'short' else 0
            def создать_с_отказом(родитель, имя, байты, режим, профиль):
                if имя == 'данные-00000.txt':
                    with patch.object(материализация.os, 'write', side_effect=запись):
                        return создать_файл(родитель, имя, байты, режим, профиль)
                return создать_файл(родитель, имя, байты, режим, профиль)
            with patch.object(материализация, '_создать_файл', side_effect=создать_с_отказом), сам.assertRaises((ОшибкаВхода, OSError)):
                материализация.материализовать(**{**параметры, 'назначение': цель, 'квитанция': квитанция})
            сам.assertFalse(квитанция.exists())

    def test_отказ_каждой_синхронизации_не_принимается(сам):
        параметры = сам.параметры(); настоящий = os.fsync
        with patch.object(материализация.os, 'fsync', wraps=настоящий) as вызовы:
            материализация.материализовать(**параметры)
        for номер in range(1, вызовы.call_count + 1):
            счётчик = 0
            def синхронизация(дескриптор):
                nonlocal счётчик
                счётчик += 1
                if счётчик == номер: raise OSError(errno.ENOSPC, 'synthetic fsync')
                return настоящий(дескриптор)
            другие = {**параметры, 'назначение': сам.папка / ('target-f' + str(номер)), 'квитанция': сам.папка / ('receipt-f' + str(номер))}
            with сам.subTest(номер=номер), patch.object(материализация.os, 'fsync', side_effect=синхронизация), сам.assertRaises((ОшибкаВхода, OSError)):
                материализация.материализовать(**другие)
            with сам.assertRaises((ОшибкаВхода, OSError)): материализация.проверить_материализацию(**другие)



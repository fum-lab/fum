    def test_чужое_назначение_ссылка_и_хранилища_не_трогаются(сам):
        параметры = сам.параметры()
        внешний = сам.папка / 'чужой'; внешний.mkdir()
        контроль = внешний / 'контроль'; контроль.write_bytes(b'keep')
        сам.назначение.symlink_to(внешний, target_is_directory=True)
        with сам.assertRaises((ОшибкаВхода, OSError)): материализация.материализовать(**параметры)
        сам.назначение.unlink(); сам.назначение.mkdir(); (сам.назначение / 'чужой').write_bytes(b'keep')

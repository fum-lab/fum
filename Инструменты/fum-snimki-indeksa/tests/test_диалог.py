import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from канон import ОшибкаВхода, прочитать
from диалог import экспортировать


ЗАДАЧА = '00000000-0000-4000-8000-000000000001'


def строка_события(тип, содержимое):
    return (json.dumps({'type': тип, 'payload': содержимое}, ensure_ascii=False) + '\n').encode()


def сообщение(роль, текст):
    return строка_события('response_item', {'type': 'message', 'role': роль,
        'phase': 'final_answer' if роль == 'assistant' else None,
        'internal_chat_message_metadata_passthrough': {'content_item_kinds': ['user.text']} if роль == 'user' else {},
        'content': [{'type': 'input_text' if роль == 'user' else 'output_text', 'text': текст}]})


class ГраницаДиалога(unittest.TestCase):
    def источник(сам):
        return строка_события('session_meta', {'id': ЗАДАЧА}) + b''.join(
            сообщение('user', 'одинаково') for номер in range(2))

    def test_повторы_порядок_завершённый_префикс_и_поздний_хвост(сам):
        префикс = сам.источник()
        хвост = сообщение('user', 'поздно')
        экспорт, квитанция = экспортировать(префикс + хвост[:-1], ЗАДАЧА)
        сообщения = прочитать(экспорт)['сообщения']
        сам.assertEqual([часть['номер'] for часть in сообщения], [1, 2])
        сам.assertEqual([часть['текст'] for часть in сообщения], ['одинаково'] * 2)
        сам.assertEqual(квитанция['граница_байтов'], len(префикс))
        прежний, повтор = экспортировать(префикс + хвост, ЗАДАЧА, квитанция=квитанция, закрепить=True)
        сам.assertEqual((прежний, повтор), (экспорт, квитанция))
        новый, новая = экспортировать(префикс + хвост, ЗАДАЧА, квитанция=квитанция)
        сам.assertEqual([часть['номер'] for часть in прочитать(новый)['сообщения']], [1, 2, 3])
        сам.assertGreater(новая['граница_байтов'], квитанция['граница_байтов'])

    def test_внутренние_и_дублирующие_события_не_экспортируются(сам):
        данные = сам.источник()
        данные += строка_события('event_msg', {'type': 'user_message', 'message': 'одинаково'})
        данные += строка_события('event_msg', {'type': 'agent_reasoning', 'text': 'скрыто'})
        данные += сообщение('assistant', 'Видимый ответ')
        экспорт, _ = экспортировать(данные, ЗАДАЧА)
        сам.assertEqual(len(прочитать(экспорт)['сообщения']), 3)
        сам.assertEqual(прочитать(экспорт)['сообщения'][-1]['роль'], 'assistant')

    def test_логическое_значение_не_является_номером_курсора(сам):
        данные = сам.источник()
        _, квитанция = экспортировать(данные, ЗАДАЧА)
        квитанция['позиции'][0]['номер'] = True
        with сам.assertRaises(ОшибкаВхода): экспортировать(данные, ЗАДАЧА, квитанция=квитанция)

    def test_повреждение_префикса_чужая_задача_и_битая_строка(сам):
        исходный = сам.источник()
        _, квитанция = экспортировать(исходный, ЗАДАЧА)
        for данные, задача in [(исходный.replace('одинаково'.encode(), 'подменено'.encode()), ЗАДАЧА), (исходный, '00000000-0000-4000-8000-000000000002'), (исходный + b'{broken}\n', ЗАДАЧА), (исходный + b'{"type":"a","type":"b"}\n', ЗАДАЧА)]:
            with сам.subTest(данные=данные), сам.assertRaises(ОшибкаВхода):
                экспортировать(данные, задача, квитанция=квитанция)


if __name__ == '__main__':
    unittest.main()

"""Аннотации видимого ответа сохраняются отдельно от роли и происхождения."""
import copy
import tempfile
import unittest
from pathlib import Path

from test_диалог import ЗАДАЧА, сообщение, строка_события
from канон import ОшибкаВхода, прочитать, кодировать, хэш
from диалог import проверить_экспорт
from поток_диалога import экспортировать_файл


class АннотацииАссистента(unittest.TestCase):
    def setUp(сам):
        временный = tempfile.TemporaryDirectory(); сам.addCleanup(временный.cleanup)
        сам.файл = Path(временный.name).resolve()/'источник.jsonl'
        сам.префикс = строка_события('session_meta', {'id':ЗАДАЧА})+сообщение('user','Начать')
        сам.ответ = {'type':'message','role':'assistant','phase':'final_answer','content':[{'type':'output_text','text':'Один ёж'}]}

    def экспорт(сам, ответ):
        сам.файл.write_bytes(сам.префикс+строка_события('response_item',ответ))
        return экспортировать_файл(сам.файл,ЗАДАЧА)

    def с_видами(сам, виды):
        return dict(сам.ответ, internal_chat_message_metadata_passthrough={'content_item_kinds':виды})

    def test_отсутствие_и_наблюдённый_неуказанный_вид_не_сливаются(сам):
        без_видов, _ = сам.экспорт(сам.ответ)
        с_видами, _ = сам.экспорт(сам.с_видами(['unknown']))
        сам.assertNotEqual(без_видов,с_видами)
        запись = прочитать(с_видами)['сообщения'][-1]
        сам.assertEqual(запись['виды_частей'],['unknown'])
        сам.assertEqual(запись['происхождение'],'ответ ассистента')
        сам.assertEqual(запись['роль'],'assistant')
        сам.assertNotEqual(запись['хэш_частей'],прочитать(без_видов)['сообщения'][-1]['хэш_частей'])

    def test_два_разных_массива_не_дают_одинаковый_успешный_экспорт(сам):
        сам.экспорт(сам.с_видами(['unknown']))
        with сам.assertRaises(ОшибкаВхода): сам.экспорт(сам.с_видами(['user.text']))

    def test_неизвестные_неполные_и_повреждённые_аннотации(сам):
        for виды in (None,[],['unknown','unknown'],'unknown',{},[None],[1],['future.kind'],['assistant.text'],['user.image']):
            with сам.subTest(виды=виды), сам.assertRaises(ОшибкаВхода): сам.экспорт(сам.с_видами(виды))
        for метаданные in ([],1,'unknown'):
            with сам.subTest(метаданные=метаданные), сам.assertRaises(ОшибкаВхода):
                сам.экспорт(dict(сам.ответ,internal_chat_message_metadata_passthrough=метаданные))

    def test_полный_массив_и_порядок_частей_сохраняются(сам):
        ответ = сам.с_видами(['unknown','unknown'])
        ответ['content'] = [{'type':'output_text','text':''},{'type':'output_text','text':'Ёж\\n'}]
        ожидаемый = copy.deepcopy(ответ)
        байты, _ = сам.экспорт(ответ)
        запись = прочитать(байты)['сообщения'][-1]
        сам.assertEqual(запись['части'],ответ['content'])
        сам.assertEqual(запись['виды_частей'],['unknown','unknown'])
        сам.assertEqual(ответ,ожидаемый)
        сам.assertEqual(проверить_экспорт(прочитать(байты),ЗАДАЧА)[-1],запись)

    def test_подмена_массива_после_пересчёта_хэша_отвергается(сам):
        байты, _ = сам.экспорт(сам.с_видами(['unknown']))
        экспорт = прочитать(байты)
        запись=экспорт['сообщения'][-1]
        запись['виды_частей']=['user.text']
        состав=кодировать({ключ:запись[ключ] for ключ in ('роль','фаза','части','виды_частей')})
        запись['байтовая_длина']=len(состав);запись['хэш_частей']=хэш(состав)
        with сам.assertRaises(ОшибкаВхода): проверить_экспорт(экспорт,ЗАДАЧА)

    def test_прежняя_форма_без_видов_и_видимые_фазы(сам):
        исходный, курсор = сам.экспорт(сам.ответ)
        for метаданные in (None,{}, {'прочее':'не свидетельство'}):
            сам.assertEqual(сам.экспорт(dict(сам.ответ,internal_chat_message_metadata_passthrough=метаданные))[0],исходный)
        for фаза in ('commentary','final','final_answer'):
            байты,_=сам.экспорт(dict(сам.с_видами(['unknown']),phase=фаза))
            сам.assertEqual(прочитать(байты)['сообщения'][-1]['фаза'],фаза)
        сам.экспорт(сам.ответ)
        сам.assertEqual(экспортировать_файл(сам.файл,ЗАДАЧА,квитанция=курсор,закрепить=True),(исходный,курсор))

    def test_незаконченный_хвост_не_теряет_виды_после_завершения(сам):
        сам.файл.write_bytes(сам.префикс)
        _,курсор=экспортировать_файл(сам.файл,ЗАДАЧА)
        хвост=строка_события('response_item',сам.с_видами(['unknown']))
        сам.файл.write_bytes(сам.префикс+хвост[:-1])
        _,незаконченный=экспортировать_файл(сам.файл,ЗАДАЧА,квитанция=курсор)
        сам.assertEqual(курсор,незаконченный)
        сам.файл.write_bytes(сам.префикс+хвост)
        байты,новый=экспортировать_файл(сам.файл,ЗАДАЧА,квитанция=курсор)
        сам.assertEqual(len(новый['позиции']),2)
        сам.assertEqual(прочитать(байты)['сообщения'][-1]['виды_частей'],['unknown'])

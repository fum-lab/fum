    def test_новая_очередь_хранит_только_поздний_хвост(сам):
        from очередь import Очередь
        from test_очередь import СНИМОК
        _, курсор = экспортировать_файл(сам.файл, ЗАДАЧА)
        хвост = сообщение('user', 'поздно')
        сам.файл.write_bytes(сам.начало + хвост[:-1])
        очередь = Очередь.создать(сам.корень/'очередь', сам.файл, ЗАДАЧА, СНИМОК, 'a'*64, курсор, [])
        начало = json.loads((очередь.каталог/'события.jsonl').read_bytes().splitlines()[0])
        сам.assertEqual(bytes.fromhex(начало['данные']['байты']), хвост[:-1])
        сам.assertEqual(очередь.привязка['схема'], 'fum.очередь-поздних-команд.2')
        связь = lambda запрос: {'запрос':запрос,'состояние':'доступен','решения':[]}
        сам.assertIsNone(очередь.барьер(связь)['барьер'])
        сам.файл.write_bytes(сам.начало + хвост)
        доставка = очередь.доставить(связь)
        сам.assertEqual(доставка['ссылка']['начало'], len(сам.начало))
        сам.assertEqual(bytes.fromhex(доставка['сырая_строка']), хвост)
        сам.файл.write_bytes(сам.начало.replace('начать'.encode(), 'забыть'.encode()) + хвост)
        сам.assertIsNone(очередь.барьер(связь)['барьер'])


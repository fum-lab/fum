    def test_экспорт_частей_в_закреплённом_входе(сам):
        from фикстуры import создать, заменить_манифест
        from вход import проверить_вход, РеестрВходов
        from канон import конверт
        репозиторий = сам.корень/'repo'
        вход = создать(репозиторий)
        части = [{'type':'input_text','text':'Ёж'}, {'type':'input_image','image_url':'opaque'}]
        сам.файл.write_bytes(строка_события('session_meta', {'id':ЗАДАЧА}) + строка_события('response_item', составное(части,['user.text','user.image'])))
        экспорт, _ = экспортировать_файл(сам.файл, ЗАДАЧА)
        заменить_манифест(репозиторий, вход, 'граница_команд', прочитать(экспорт))
        байты = кодировать(вход)
        результат = проверить_вход(репозиторий, байты, кодировать(конверт(байты)), ожидаемый_коммит=вход['исходный_коммит'], ожидаемая_ветка=вход['исходная_ветка'], реестр=РеестрВходов(сам.корень/'реестр',репозиторий))
        сам.assertFalse(результат['исполнение_разрешено'])
        сам.assertFalse(результат['коммит_разрешён'])

        from материализация import материализовать, проверить_материализацию
        реестр = РеестрВходов(сам.корень/'мат-реестр',репозиторий)
        повреждённый = прочитать(экспорт)
        повреждённый['сообщения'][0]['части'][0]['text'] = 'Подмена'
        неверный = заменить_манифест(репозиторий, copy.deepcopy(вход), 'граница_команд', повреждённый)
        неверные_байты = кодировать(неверный)
        with сам.assertRaisesRegex(ОшибкаВхода, 'состав частей изменён'):
            проверить_вход(репозиторий, неверные_байты, кодировать(конверт(неверные_байты)), ожидаемый_коммит=вход['исходный_коммит'], ожидаемая_ветка=вход['исходная_ветка'], реестр=реестр)
        реестр.зарегистрировать(байты)
        (репозиторий/'команды.json').write_bytes(b'changed live checkout')
        параметры = dict(корень=репозиторий,байты=байты,оболочка=кодировать(конверт(байты)),ожидаемый_коммит=вход['исходный_коммит'],ожидаемая_ветка=вход['исходная_ветка'],реестр=реестр,локальные_зависимости={},назначение=сам.корень/'материализация',квитанция=сам.корень/'квитанция.json')
        результат = материализовать(**параметры)
        сам.assertEqual((параметры['назначение']/'команды.json').read_bytes(), экспорт)
        сам.assertEqual(результат, проверить_материализацию(**параметры))
        сам.assertFalse(результат['исполнение_разрешено'])


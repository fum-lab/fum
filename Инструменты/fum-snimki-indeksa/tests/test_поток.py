def составное(части, виды):
    return {'type': 'message', 'role': 'user', 'content': части,
            'internal_chat_message_metadata_passthrough': {'content_item_kinds': виды}}


class ПотокДиалога(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory(); сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name).resolve(); сам.файл = сам.корень / 'источник.jsonl'
        сам.начало = строка_события('session_meta', {'id': ЗАДАЧА}) + сообщение('user', 'начать')
        сам.файл.write_bytes(сам.начало)

    def test_прежний_малый_экспорт_и_потоковые_позиции(сам):
        старые, прежняя = экспортировать(сам.начало, ЗАДАЧА)
        новые, курсор = экспортировать_файл(сам.файл, ЗАДАЧА)
        сам.assertEqual(курсор['позиции'], прежняя['позиции'])
        сам.assertEqual(курсор['хэш_префикса'], прежняя['хэш_префикса'])
        сам.assertEqual(прочитать(старые)['сообщения'][0]['текст'], прочитать(новые)['сообщения'][0]['части'][0]['text'])
        сам.assertEqual(экспортировать(сам.начало, ЗАДАЧА), (старые, прежняя))

    def test_части_пустые_строки_медиа_и_отсутствие_склейки(сам):
        части = [{'type':'input_text','text':'ab'}, {'type':'output_text','text':''}, {'type':'input_image','image_url':'file:///never-open'}, {'type':'input_image','image_url':'opaque','detail':None}, {'type':'input_audio','audio_url':'opaque'}]
        полезное = составное(части, ['user.text','user.text','user.image','user.image','user.audio'])
        сам.файл.write_bytes(сам.начало + строка_события('response_item', полезное))
        байты, _ = экспортировать_файл(сам.файл, ЗАДАЧА)
        сообщения = проверить_экспорт(прочитать(байты), ЗАДАЧА)
        сам.assertEqual(сообщения[-1]['части'], части)
        сам.assertEqual(len(сообщения), 2)
        подмена = прочитать(байты); подмена['сообщения'][-1]['части'].reverse()
        with сам.assertRaises(ОшибкаВхода): проверить_экспорт(подмена, ЗАДАЧА)
        with сам.assertRaises(ОшибкаВхода): экспортировать(сам.файл.read_bytes(), ЗАДАЧА)

    def test_частичный_хвост_и_старый_префикс(сам):
        _, курсор = экспортировать_файл(сам.файл, ЗАДАЧА)
        хвост = сообщение('user', 'поздний ёж')
        сам.файл.write_bytes(сам.начало + хвост[:-2])
        _, частичный = экспортировать_файл(сам.файл, ЗАДАЧА, квитанция=курсор)
        сам.assertEqual(частичный, курсор)
        сырые, _ = прочитать_хвост(сам.файл, ЗАДАЧА, курсор)
        сам.assertEqual(сырые, хвост[:-2])
        сам.файл.write_bytes(сам.начало + хвост)
        _, новый = экспортировать_файл(сам.файл, ЗАДАЧА, квитанция=курсор)
        сам.assertEqual(len(новый['позиции']), 2)
        сам.файл.write_bytes(сам.начало.replace('начать'.encode(), 'забыть'.encode()) + хвост)
        with сам.assertRaises(ОшибкаВхода): экспортировать_файл(сам.файл, ЗАДАЧА, квитанция=курсор)
        with сам.assertRaises(ОшибкаВхода): прочитать_хвост(сам.файл, ЗАДАЧА, курсор)

    def test_лимиты_классификатора_отдельны_от_объёма_текста(сам):
        длинный = составное([{'type':'input_text','text':'a' * 3_300_000}], ['user.text'])
        сам.assertEqual(классифицировать_сообщение(длинный), 'человек')
        хук = {'type':'message','role':'user','content':[{'type':'input_text','text':'<hook_prompt hook_run_id="1">' + 'a' * 262144 + '</hook_prompt>'}]}
        сам.assertEqual(классифицировать_сообщение(хук), 'неоднозначный')
        части = [{'type':'input_text','text':''}] * 256
        сам.assertEqual(классифицировать_сообщение(составное(части, ['user.text'] * 256)), 'человек')
        сам.assertEqual(классифицировать_сообщение(составное(части + части[:1], ['user.text'] * 257)), 'неоднозначный')

    def test_конечные_раздельные_бюджеты_без_усечения(сам):
        with mock.patch('поток_диалога.ПРЕДЕЛ_ПЕРВИЧНОГО_ИСТОЧНИКА', len(сам.начало) - 1), сам.assertRaises(ОшибкаВхода): экспортировать_файл(сам.файл, ЗАДАЧА)

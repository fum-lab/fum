"""Повторяемые размеры/байты, отдельные этапы, число чтений и Python heap peak."""
import argparse
import json
import platform
import subprocess
import tempfile
import tracemalloc
from pathlib import Path
from time import perf_counter_ns

from фикстуры import создать, гит
from test_материализация import обновить, добавить_зависимость
from канон import кодировать, конверт, хэш
from вход import РеестрВходов
from профиль import Профиль
from материализация import материализовать, проверить_материализацию


def выполнить():
    разбор = argparse.ArgumentParser()
    разбор.add_argument('--размеры', default='2,100')
    разбор.add_argument('--выход', required=True, type=Path)
    разбор.add_argument('--сравнить', type=Path)
    параметры = разбор.parse_args()
    источник = Path(__file__).resolve().parents[1]
    замеры = []
    for размер in map(int, параметры.размеры.split(',')):
        for вид in ('повторные', 'уникальные'):
            with tempfile.TemporaryDirectory() as временный:
                папка = Path(временный).resolve(); корень = папка / 'source'
                начало = perf_counter_ns()
                вход = создать(корень, размер)
                for номер in range(размер):
                    файл = корень / f'данные-{номер:05}.txt'
                    префикс = (str(номер) if вид == 'уникальные' else 'X').encode()
                    файл.write_bytes(префикс + b'a' * (4096 - len(префикс)))
                    файл.chmod(0o755 if номер % 2 else 0o644)
                гит(корень, 'add', '.')
                обновить(корень, вход)
                зависимости = добавить_зависимость(корень, вход, папка / 'dependency')
                байты = кодировать(вход)
                реестр = РеестрВходов(папка / 'registry', корень); реестр.зарегистрировать(байты)
                подготовка = perf_counter_ns() - начало
                аргументы = dict(корень=корень, байты=байты, оболочка=кодировать(конверт(байты)),
                    ожидаемый_коммит=вход['исходный_коммит'], ожидаемая_ветка=вход['исходная_ветка'], реестр=реестр,
                    назначение=папка / 'target', квитанция=папка / 'receipt', локальные_зависимости=зависимости)
                профиль = Профиль(); tracemalloc.start(); начало = perf_counter_ns()
                результат = материализовать(**аргументы, профиль=профиль)
                длительность = perf_counter_ns() - начало
                _, пик = tracemalloc.get_traced_memory(); tracemalloc.stop()
                повторный = Профиль(); начало = perf_counter_ns()
                проверенный = проверить_материализацию(**аргументы, профиль=повторный)
                повтор = perf_counter_ns() - начало
                assert проверенный == результат
                манифест = {'файлы': результат['файлы'], 'каталоги': результат['каталоги']}
                замеры.append({'размер': размер, 'вид': вид, 'зависимость': True, 'байт_в_дополнительном_объекте': 4096,
                    'подготовка_наносекунды': подготовка, 'материализация_наносекунды': длительность, 'повторная_сверка_наносекунды': повтор,
                    'пик_памяти_python_байты': пик, 'хэш_входа': хэш(байты), 'хэш_манифеста': хэш(кодировать(манифест)),
                    'файлы': len(результат['файлы']), 'байты': sum(файл['длина'] for файл in результат['файлы']),
                    'счётчики': профиль.счётчики, 'измерения': профиль.измерения,
                    'метки': профиль.записи, 'метки_повторной_сверки': повторный.записи})
    if параметры.сравнить:
        прежние = json.loads(параметры.сравнить.read_text())['замеры']
        for до, после in zip(прежние, замеры, strict=True):
            for поле in ('размер', 'вид', 'хэш_входа', 'хэш_манифеста', 'файлы', 'байты'):
                assert до[поле] == после[поле], 'изменились точные условия: ' + поле
    результат = {'схема': 'fum.профиль-материализации.1', 'python': platform.python_version(),
        'git': subprocess.check_output(['git', '--version'], text=True).strip(),
        'условия': 'monotonic wall-clock; вложенные метки не складываются; tracemalloc измеряет только Python heap текущего процесса, без памяти дочернего Git; каждый вход перепроверяется свежими читателями; 0644/0755, raw dependency; Git-счётчики включают проверки входа и чтение материализации, но не служебный rev-parse',
        'версии_файлов': {файл.relative_to(источник).as_posix(): хэш(файл.read_bytes()) for файл in sorted(источник.rglob('*.py'))}, 'замеры': замеры}
    параметры.выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + '\n')
    for замер in замеры:
        print(замер['размер'], замер['вид'], round(замер['материализация_наносекунды']/1e9, 3), 'с,', замер['файлы'], 'файлов,', замер['счётчики']['чтения_git'], 'чтений Git')


if __name__ == '__main__': выполнить()

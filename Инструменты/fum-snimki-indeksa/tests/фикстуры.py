ЗАДАЧА = '00000000-0000-4000-8000-000000000001'
РАУНД = '00000000-0000-4000-8000-000000000002'


def гит(корень, *аргументы, вход=None):
    return subprocess.run(['git', '-C', str(корень), *аргументы], input=вход, capture_output=True, check=True, env={**os.environ, 'GIT_AUTHOR_DATE': '2026-01-01T00:00:00+00:00', 'GIT_COMMITTER_DATE': '2026-01-01T00:00:00+00:00'}).stdout


def создать(корень, количество=1, алгоритм='sha1'):
    корень = Path(корень).resolve()
    корень.mkdir(exist_ok=True)
    гит(корень, 'init', '-q', '-b', 'fixture', '--object-format=' + алгоритм)
    гит(корень, 'config', 'user.name', 'Fixture')
    гит(корень, 'config', 'user.email', 'fixture@example.invalid')
    (корень / 'запрос.md').write_text('Исходная команда\n')
    (корень / 'отчёт.md').write_text('Подготовка\n')
    (корень / 'правила.md').write_text('Сырые входы\n')
    (корень / 'инструмент.py').write_text('print("fixture")\n')
    for номер in range(количество):
        (корень / f'данные-{номер:05}.txt').write_text('байты\n' * 20)
    события = [
        {'type': 'session_meta', 'payload': {'id': ЗАДАЧА}},
        {'type': 'response_item', 'payload': {'type': 'message', 'role': 'user',
          'internal_chat_message_metadata_passthrough': {'content_item_kinds': ['user.text']},
          'content': [{'type': 'input_text', 'text': 'Проверить синтетический вход'}]}},
    ]
    диалог = b''.join((json.dumps(событие, ensure_ascii=False) + '\n').encode() for событие in события)
    экспорт, _ = экспортировать(диалог, ЗАДАЧА)
    (корень / 'команды.json').write_bytes(экспорт)
    среда = {'схема': 'fum.среда-снимка.1', 'компоненты': [{'имя': 'Python', 'версия': 'fixture', 'команда': 'python3'}], 'ограничения': ['Синтетическая среда без исполнения']}
    (корень / 'среда.json').write_bytes(кодировать(среда))
    политика = {'схема': 'fum.выход-снимка.1', 'результаты': []}
    (корень / 'политика.json').write_bytes(кодировать(политика))
    гит(корень, 'add', '.')
    гит(корень, 'commit', '-qm', 'fixture')
    объекты = ОбъектыГит(корень)
    коммит = объекты.оид(гит(корень, 'rev-parse', 'HEAD').decode().strip())
    дерево = объекты.дерево_коммита(коммит)
    источники = sorted([имя for имя in объекты.дерево(дерево)] + ['план.json'], key=lambda имя: имя.encode())
    план = {'схема': 'fum.план-снимка.1', 'шаги': [{'номер': 1, 'аргументы': ['python3', 'инструмент.py'], 'класс': 'адресная', 'зависит_от': [], 'ожидаемый_исход': 0,
            'ссылки_на_инструменты': [объекты.ссылка(дерево, 'инструмент.py')], 'ссылки_на_правила': [объекты.ссылка(дерево, 'правила.md')]}],
            'происхождение': [{'путь': имя, 'вид': 'непрозрачные_байты', 'зависит_от': []} for имя in источники]}
    (корень / 'план.json').write_bytes(кодировать(план))
    гит(корень, 'add', 'план.json')
    дерево = подготовить_дерево(корень, коммит, 'refs/heads/fixture')
    вход = {'версия': 'fum.вход-снимка.1', 'вид': 'вход', 'идентификатор_задачи': ЗАДАЧА,
            'идентификатор_раунда': РАУНД, 'предыдущая_квитанция': None, 'запрос': 'запрос.md', 'отчёт': 'отчёт.md',
            'исходный_коммит': коммит, 'исходная_ветка': 'refs/heads/fixture', 'дерево_входа': дерево,
            'граница_команд': объекты.ссылка(дерево, 'команды.json'),
            'основание_полномочий': [{'номер_сообщения': 1, 'действия': ['проверка_байтов']}],
            'зависимости': [], 'профиль_среды': объекты.ссылка(дерево, 'среда.json'),
            'план_проверок': объекты.ссылка(дерево, 'план.json'), 'политика_выхода': объекты.ссылка(дерево, 'политика.json')}
    return вход


def заменить_манифест(корень, вход, поле, значение):
    имя = вход[поле]['путь']
    (корень / имя).write_bytes(кодировать(значение))
    гит(корень, 'add', имя)
    вход['дерево_входа'] = подготовить_дерево(корень, вход['исходный_коммит'], вход['исходная_ветка'])
    объекты = ОбъектыГит(корень)
    вход[поле] = объекты.ссылка(вход['дерево_входа'], имя)
    return вход

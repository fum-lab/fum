РАЗМЕР = 105356966
СТРОК = 16609
ДЛИННАЯ_СТРОКА = 3326896


def создать_источник(путь):
    начало = строка_события('session_meta', {'id': ЗАДАЧА})
    длинная = сообщение('user', 'a' * (ДЛИННАЯ_СТРОКА - len(сообщение('user', ''))))
    части = [{'type':'input_text','text':'Ёж'}, {'type':'output_text','text':''}, {'type':'input_image','image_url':'https://example.invalid/public-fixture','detail':None}, {'type':'input_audio','audio_url':'opaque-public-fixture'}]
    составная = строка_события('response_item', составное(части, ['user.text','user.text','user.image','user.audio']))
    оболочка = строка_события('event_msg', {'type':'synthetic_filler','text':''})
    базовая, добавочных = divmod(РАЗМЕР-len(начало)-len(длинная)-len(составная), СТРОК-3)
    заполнители = [строка_события('event_msg', {'type':'synthetic_filler','text':'x'*(базовая+добавка-len(оболочка))}) for добавка in (0,1)]
    хэшер = hashlib.sha256(); размер = 0; строк = 0; максимум = 0
    with путь.open('wb') as поток:
        for запись in (начало, длинная, составная):
            поток.write(запись); хэшер.update(запись); размер+=len(запись); строк+=1; максимум=max(максимум,len(запись))
        for номер in range(СТРОК-3):
            запись = заполнители[int(номер<добавочных)]
            поток.write(запись); хэшер.update(запись); размер+=len(запись); строк+=1; максимум=max(максимум,len(запись))
    assert (размер,строк,максимум)==(РАЗМЕР,СТРОК,ДЛИННАЯ_СТРОКА)
    return {'байтов':размер,'завершённых_строк':строк,'максимальная_строка_с_LF':максимум,'sha256':хэшер.hexdigest(),'части_второго_сообщения':части,'задача':ЗАДАЧА}


def версии():
    корень = Path(__file__).resolve().parents[1]
    return {путь.relative_to(корень).as_posix():хэш(путь.read_bytes()) for путь in sorted(корень.rglob('*.py'))}


def ожидать_отказ(действие):
    try: действие()
    except ОшибкаВхода: return True
    raise AssertionError('Ожидаемый отказ отсутствует')


def выполнить(параметры):
    исходные_версии = версии()
    with tempfile.TemporaryDirectory() as временный:
        корень = Path(временный).resolve(); источник = корень/'публичная-синтетика.jsonl'
        манифест = создать_источник(источник)
        if параметры.прежний_читатель:
            print(json.dumps({'манифест':манифест,'проверка':'Прежний читатель должен пропустить требуемый размер; ожидаемый фактический RED по лимиту64МиБ'},ensure_ascii=False),flush=True)
            _источник(источник)
            raise AssertionError('Прежнее ограничение неожиданно отсутствует')
        замеры = ЗамерыПотока()
        tracemalloc.start(); начало = perf_counter_ns()
        экспорт, курсор = экспортировать_файл(источник, ЗАДАЧА, профиль=замеры)
        длительность = perf_counter_ns()-начало
        текущая, последний_пик = tracemalloc.get_traced_memory(); tracemalloc.stop()
        проверка = json.loads(экспорт)
        assert курсор['граница_байтов']==РАЗМЕР and курсор['хэш_префикса']==манифест['sha256']
        assert len(проверка['сообщения'])==2
        assert len(проверка['сообщения'][0]['части'][0]['text'])==ДЛИННАЯ_СТРОКА-len(сообщение('user',''))
        assert проверка['сообщения'][1]['части']==манифест['части_второго_сообщения']
        манифест.update(экспорт_байтов=len(экспорт),экспорт_sha256=хэш(экспорт),курсор=курсор)
        начало = perf_counter_ns()
        очередь = Очередь.создать(корень/'очередь', источник, ЗАДАЧА, СНИМОК, 'a'*64, курсор, [])
        журнал = очередь.каталог/'события.jsonl'
        генезис = json.loads(журнал.read_bytes().splitlines()[0])
        assert генезис['данные']['байты']==''
        размер_генезиса = журнал.stat().st_size
        assert размер_генезиса<16384
        решения=[]
        связь=lambda запрос:{'запрос':запрос,'состояние':'доступен','решения':решения}
        старый=очередь.барьер(связь)['барьер']; assert старый is not None
        хвост=сообщение('user','поздний публичный ёж')
        with источник.open('ab') as поток: поток.write(хвост[:-1])
        assert очередь.доставить(связь) is None
        assert очередь.барьер(связь)['барьер'] is None
        assert прочитать_хвост(источник,ЗАДАЧА,курсор)[0]==хвост[:-1]
        with источник.open('ab') as поток: поток.write(b'\n')
        доставка=очередь.доставить(связь)
        assert доставка['ссылка']['начало']==РАЗМЕР and bytes.fromhex(доставка['сырая_строка'])==хвост
        решения.append({'идентификатор':'00000000-0000-4000-8000-000000000003','ссылка':доставка['ссылка'],'действие':'учесть','разрешения':None})
        очередь.подтвердить(доставка['ссылка'],связь)
        assert очередь.доставить(связь) is None
        результат=очередь.барьер(связь)
        assert результат['барьер'] is not None and результат['исполнение_разрешено'] is False
        assert очередь.проверить_барьер(результат['барьер'],связь)['совпадает']
        assert not очередь.проверить_барьер(старый,связь)['совпадает']
        with источник.open('r+b') as поток:
            поток.seek(РАЗМЕР-3); исходный=поток.read(1); поток.seek(РАЗМЕР-3); поток.write(b'y')
        ожидать_отказ(lambda:прочитать_хвост(источник,ЗАДАЧА,курсор))
        assert очередь.барьер(связь)['барьер'] is None
        длительность_очереди=perf_counter_ns()-начало
        with источник.open('r+b') as поток:
            поток.seek(РАЗМЕР-3); поток.write(исходный); поток.truncate(РАЗМЕР)
        хэшер=hashlib.sha256()
        with источник.open('rb') as поток:
            while часть:=поток.read(1024*1024): хэшер.update(часть)
        assert хэшер.hexdigest()==манифест['sha256']
        assert версии()==исходные_версии, 'Код изменился во время профиля'
        сведения={'схема':'fum.профиль-потокового-диалога.1','python':platform.python_version(),'платформа':platform.platform(),'версии_файлов':исходные_версии,
          'экспорт_наносекунд':длительность,'операции':{имя:{'наносекунд':замеры.наносекунды[имя],'вызовов':замеры.счётчики[имя],'дополнительный_пик_python_байтов':замеры.дополнительная_память[имя]} for имя in замеры.наносекунды},
          'максимум_наблюдённых_пиков_python_байтов':max(замеры.пик_памяти,последний_пик),'оставшаяся_python_память_байтов':текущая,
          'максимум_rss_процесса_байтов':resource.getrusage(resource.RUSAGE_SELF).ru_maxrss*(1 if sys.platform=='darwin' else 1024),
          'цикл_очереди_без_tracemalloc_наносекунд':длительность_очереди,'генезис_очереди_байтов':размер_генезиса,'итоговый_wal_байтов':журнал.stat().st_size,
          'синтетика_sha256':манифест['sha256'],'экспорт_sha256':хэш(экспорт),'исполнение_разрешено':False,
          'проверки': ['точный размер/строки/длинная строка','порядок всех частей','SHA полного завершённого префикса','WAL без основания','незаконченный хвост не доставляется','завершение/доставка/решение/подтверждение ровно один раз','старое поколение отвергнуто','свежий барьер не разрешает исполнение','изменение старых байтов отвергнуто','финальное восстановление SHA синтетики','исходники не изменились во время профиля']}
        параметры.манифест.write_text(json.dumps(манифест,ensure_ascii=False,indent=2)+'\n')
        параметры.профиль.write_text(json.dumps(сведения,ensure_ascii=False,indent=2)+'\n')
        print(json.dumps({'экспорт_секунд':длительность/1e9,'цикл_очереди_секунд':длительность_очереди/1e9,'манифест':str(параметры.манифест),'профиль':str(параметры.профиль)},ensure_ascii=False))



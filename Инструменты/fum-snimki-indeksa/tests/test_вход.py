import copy
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from канон import ОшибкаВхода, кодировать, конверт, прочитать
from фикстуры import создать, гит, заменить_манифест
from объекты import ОбъектыГит
from вход import проверить_вход, допустить_исполнение, РеестрВходов


class ЗакрытыйВход(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name).resolve() / 'repo'
        сам.вход = создать(сам.корень)
        сам.реестр = РеестрВходов(Path(сам.временный.name).resolve() / 'registry', сам.корень)

    def проверить(сам, вход=None):
        запись = сам.вход if вход is None else вход
        байты = кодировать(запись)
        return проверить_вход(сам.корень, байты, кодировать(конверт(байты)),
            ожидаемый_коммит=сам.вход['исходный_коммит'], ожидаемая_ветка='refs/heads/fixture', реестр=сам.реестр)

    def test_чистый_вход_не_разрешает_исполнение(сам):
        результат = сам.проверить()
        сам.assertFalse(результат['исполнение_разрешено'])
        сам.assertFalse(результат['коммит_разрешён'])
        сам.assertEqual(результат['статус'], 'сырые_байты_проверены')
        with сам.assertRaises(ОшибкаВхода):
            допустить_исполнение(результат)

    def test_живые_байты_и_индекс_не_подменяют_манифест(сам):
        исходный = сам.проверить()
        for имя in ['команды.json', 'инструмент.py', 'запрос.md', 'план.json']:
            (сам.корень / имя).write_bytes(b'late bytes')
        гит(сам.корень, 'add', '.')
        сам.assertEqual(сам.проверить(), исходный)

    def test_закрытые_поля_и_полномочия(сам):
        варианты = [('лишнее', 1), ('предыдущая_квитанция', '0' * 64), ('версия', 'run-v4'), ('запрос', '../запрос.md'), ('отчёт', 'Запрос.md'),
                    ('основание_полномочий', [{'номер_сообщения': True, 'действия': ['проверка_байтов']}]),
                    ('основание_полномочий', [{'номер_сообщения': 2, 'действия': ['проверка_байтов']}]),
                    ('основание_полномочий', [{'номер_сообщения': 1, 'действия': ['публикация']}])]
        for поле, значение in варианты:
            вход = copy.deepcopy(сам.вход)
            вход[поле] = значение
            with сам.subTest(поле=поле), сам.assertRaises(ОшибкаВхода):
                сам.проверить(вход)

    def test_неполный_граф_обратные_ссылки_неизвестные_шаги(сам):
        исходный = прочитать((сам.корень / 'план.json').read_bytes())
        for вид in ['пропуск', 'обратная', 'производный', 'будущий_шаг', 'булев_шаг', 'лишнее_поле', 'подмена_инструмента']:
            план = copy.deepcopy(исходный)
            if вид == 'пропуск': план['происхождение'].pop()
            if вид == 'обратная': план['происхождение'][0]['зависит_от'] = ['.fum-приёмка/вход.json']
            if вид == 'производный': план['происхождение'][0]['вид'] = 'производный'
            if вид == 'будущий_шаг': план['шаги'][0]['зависит_от'] = [2]
            if вид == 'булев_шаг': план['шаги'][0]['номер'] = True
            if вид == 'лишнее_поле': план['шаги'][0]['неизвестное'] = 'хэш будущего входа'
            if вид == 'подмена_инструмента': план['шаги'][0]['ссылки_на_инструменты'][0]['хэш_байтов'] = '0' * 64
            вход = заменить_манифест(сам.корень, copy.deepcopy(сам.вход), 'план_проверок', план)
            with сам.subTest(вид=вид), сам.assertRaises(ОшибкаВхода): сам.проверить(вход)

    def test_подмодуль_не_подменяется_рабочими_файлами(сам):
        гит(сам.корень, 'update-index', '--add', '--cacheinfo', '160000,' + сам.вход['исходный_коммит']['значение'] + ',зависимость')
        вход = copy.deepcopy(сам.вход)
        вход['дерево_входа'] = ОбъектыГит(сам.корень).оид(гит(сам.корень, 'write-tree').decode().strip())
        with сам.assertRaises(ОшибкаВхода): сам.проверить(вход)

    def test_повтор_идентификатора_с_другими_байтами(сам):
        байты = кодировать(сам.вход)
        сам.проверить()
        сам.реестр.зарегистрировать(байты)
        сам.реестр.зарегистрировать(байты)
        сам.проверить()
        другой = copy.deepcopy(сам.вход)
        другой['основание_полномочий'].append({'номер_сообщения': 1, 'действия': ['подготовка_дерева']})
        with сам.assertRaises(ОшибкаВхода): сам.проверить(другой)
        with сам.assertRaises(ОшибкаВхода): сам.реестр.зарегистрировать(кодировать(другой))

    def test_запись_и_конверт_в_дереве_отвергаются(сам):
        (сам.корень / '.fum-приёмка').mkdir()
        (сам.корень / '.fum-приёмка/вход.json').write_bytes(кодировать(сам.вход))
        гит(сам.корень, 'add', '.')
        вход = copy.deepcopy(сам.вход)
        вход['дерево_входа'] = ОбъектыГит(сам.корень).оид(гит(сам.корень, 'write-tree').decode().strip())
        with сам.assertRaises(ОшибкаВхода): сам.проверить(вход)


if __name__ == '__main__': unittest.main()

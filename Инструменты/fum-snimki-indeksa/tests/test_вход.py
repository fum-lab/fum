import copy
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from канон import ОшибкаВхода, кодировать, конверт, прочитать
from фикстуры import создать, гит, заменить_манифест
from объекты import ОбъектыГит
from вход import проверить_вход, допустить_исполнение, РеестрВходов


class ЗакрытыйВход(unittest.TestCase):
    def setUp(self):
        self.временный = tempfile.TemporaryDirectory()
        self.addCleanup(self.временный.cleanup)
        self.корень = Path(self.временный.name).resolve() / 'repo'
        self.вход = создать(self.корень)
        self.реестр = РеестрВходов(Path(self.временный.name).resolve() / 'registry', self.корень)

    def проверить(self, вход=None):
        запись = self.вход if вход is None else вход
        байты = кодировать(запись)
        return проверить_вход(self.корень, байты, кодировать(конверт(байты)),
            ожидаемый_коммит=self.вход['исходный_коммит'], ожидаемая_ветка='refs/heads/fixture', реестр=self.реестр)

    def test_чистый_вход_не_разрешает_исполнение(self):
        результат = self.проверить()
        self.assertFalse(результат['исполнение_разрешено'])
        self.assertFalse(результат['коммит_разрешён'])
        self.assertEqual(результат['статус'], 'сырые_байты_проверены')
        with self.assertRaises(ОшибкаВхода):
            допустить_исполнение(результат)

    def test_живые_байты_и_индекс_не_подменяют_манифест(self):
        исходный = self.проверить()
        for имя in ['команды.json', 'инструмент.py', 'запрос.md', 'план.json']:
            (self.корень / имя).write_bytes(b'late bytes')
        гит(self.корень, 'add', '.')
        self.assertEqual(self.проверить(), исходный)

    def test_закрытые_поля_и_полномочия(self):
        варианты = [('лишнее', 1), ('предыдущая_квитанция', '0' * 64), ('версия', 'run-v4'), ('запрос', '../запрос.md'), ('отчёт', 'Запрос.md'),
                    ('основание_полномочий', [{'номер_сообщения': True, 'действия': ['проверка_байтов']}]),
                    ('основание_полномочий', [{'номер_сообщения': 2, 'действия': ['проверка_байтов']}]),
                    ('основание_полномочий', [{'номер_сообщения': 1, 'действия': ['публикация']}])]
        for поле, значение in варианты:
            вход = copy.deepcopy(self.вход)
            вход[поле] = значение
            with self.subTest(поле=поле), self.assertRaises(ОшибкаВхода):
                self.проверить(вход)

    def test_неполный_граф_обратные_ссылки_неизвестные_шаги(self):
        исходный = прочитать((self.корень / 'план.json').read_bytes())
        for вид in ['пропуск', 'обратная', 'производный', 'будущий_шаг', 'булев_шаг', 'лишнее_поле', 'подмена_инструмента']:
            план = copy.deepcopy(исходный)
            if вид == 'пропуск': план['происхождение'].pop()
            if вид == 'обратная': план['происхождение'][0]['зависит_от'] = ['.fum-приёмка/вход.json']
            if вид == 'производный': план['происхождение'][0]['вид'] = 'производный'
            if вид == 'будущий_шаг': план['шаги'][0]['зависит_от'] = [2]
            if вид == 'булев_шаг': план['шаги'][0]['номер'] = True
            if вид == 'лишнее_поле': план['шаги'][0]['неизвестное'] = 'хэш будущего входа'
            if вид == 'подмена_инструмента': план['шаги'][0]['ссылки_на_инструменты'][0]['хэш_байтов'] = '0' * 64
            вход = заменить_манифест(self.корень, copy.deepcopy(self.вход), 'план_проверок', план)
            with self.subTest(вид=вид), self.assertRaises(ОшибкаВхода): self.проверить(вход)

    def test_gitlink_не_подменяется_checkout(self):
        гит(self.корень, 'update-index', '--add', '--cacheinfo', '160000,' + self.вход['исходный_коммит']['значение'] + ',зависимость')
        вход = copy.deepcopy(self.вход)
        вход['дерево_входа'] = ОбъектыГит(self.корень).оид(гит(self.корень, 'write-tree').decode().strip())
        with self.assertRaises(ОшибкаВхода): self.проверить(вход)

    def test_повтор_uuid_с_другими_байтами(self):
        байты = кодировать(self.вход)
        self.проверить()
        self.реестр.зарегистрировать(байты)
        self.реестр.зарегистрировать(байты)
        self.проверить()
        другой = copy.deepcopy(self.вход)
        другой['основание_полномочий'].append({'номер_сообщения': 1, 'действия': ['подготовка_дерева']})
        with self.assertRaises(ОшибкаВхода): self.проверить(другой)
        with self.assertRaises(ОшибкаВхода): self.реестр.зарегистрировать(кодировать(другой))

    def test_запись_и_конверт_в_дереве_отвергаются(self):
        (self.корень / '.fum-приёмка').mkdir()
        (self.корень / '.fum-приёмка/вход.json').write_bytes(кодировать(self.вход))
        гит(self.корень, 'add', '.')
        вход = copy.deepcopy(self.вход)
        вход['дерево_входа'] = ОбъектыГит(self.корень).оид(гит(self.корень, 'write-tree').decode().strip())
        with self.assertRaises(ОшибкаВхода): self.проверить(вход)


if __name__ == '__main__': unittest.main()

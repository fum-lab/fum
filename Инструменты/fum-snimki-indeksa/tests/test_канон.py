import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from канон import ОшибкаВхода, кодировать, прочитать, проверить_конверт, конверт


class КаноническиеБайты(unittest.TestCase):
    def test_единственное_кодирование(self):
        значение = {'я': '\n\t\b\f\r\x00/"\\😀', 'а': 9223372036854775807}
        байты = кодировать(значение)
        self.assertEqual(байты, ('{"а":9223372036854775807,"я":"\\u000a\\u0009\\u0008\\u000c\\u000d\\u0000/\\"\\\\😀"}\n').encode())
        self.assertEqual(прочитать(байты), значение)
        self.assertEqual(проверить_конверт(байты, кодировать(конверт(байты))), значение)

    def test_неоднозначные_байты_отвергаются(self):
        варианты = [b'{"a":1,"a":2}\n', b'{"a":-0}\n', b'{"a":1.0}\n', b'{"a":1e0}\n',
                    b'{"a":NaN}\n', b'{"a":Infinity}\n', b'{"a":-1}\n', b'{"a":9223372036854775808}\n',
                    b'{"a":"\\n"}\n', b'{"a":"\\/"}\n', b'{"a":"\\u0061"}\n', b'{"a":"\\uD800"}\n',
                    b'{}\r\n', b'{}', b'\xef\xbb\xbf{}\n', b'{ "a":0}\n']
        for байты in варианты:
            with self.subTest(байты=байты), self.assertRaises(ОшибкаВхода):
                прочитать(байты)

    def test_хэш_и_поля_конверта(self):
        байты = кодировать({'число': 0})
        for поле, значение in [('длина', True), ('длина', 0), ('хэш_байтов', 'f' * 64), ('лишнее', 1), ('алгоритм', 'sha1')]:
            описание = конверт(байты)
            описание[поле] = значение
            with self.subTest(поле=поле), self.assertRaises(ОшибкаВхода):
                проверить_конверт(байты, кодировать(описание))


if __name__ == '__main__':
    unittest.main()

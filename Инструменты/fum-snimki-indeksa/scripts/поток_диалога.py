СХЕМА_ЭКСПОРТА_ЧАСТЕЙ = 'fum.экспорт-команд.2'
СХЕМА_ПОТОКОВОГО_КУРСОРА = 'fum.локальная-граница-диалога.2'
ПРЕДЕЛ_ПЕРВИЧНОГО_ИСТОЧНИКА = 128 * 1024 * 1024
ПРЕДЕЛ_СТРОКИ = 4 * 1024 * 1024
ПРЕДЕЛ_ЭКСПОРТА = 64 * 1024 * 1024
ПРЕДЕЛ_ЗАПИСЕЙ = 100000
РАЗМЕР_ЧАНКА = 1024 * 1024


class ЗамерыПотока:
    """Время операций и дополнительные пики Python относительно их начала."""
    def __init__(сам):
        сам.наносекунды = {}
        сам.дополнительная_память = {}
        сам.пик_памяти = 0
        сам.счётчики = {}

    def вызвать(сам, имя, действие):
        память = tracemalloc.is_tracing()
        до = tracemalloc.get_traced_memory()[0] if память else 0
        if память: tracemalloc.reset_peak()
        начало = perf_counter_ns()
        try: return действие()
        finally:
            сам.наносекунды[имя] = сам.наносекунды.get(имя, 0) + perf_counter_ns() - начало
            сам.счётчики[имя] = сам.счётчики.get(имя, 0) + 1
            if память:
                _, пик = tracemalloc.get_traced_memory()
                сам.пик_памяти = max(сам.пик_памяти, пик)
                сам.дополнительная_память[имя] = max(сам.дополнительная_память.get(имя, 0), пик - до)


def _измерить(профиль, имя, действие):
    return профиль.вызвать(имя, действие) if профиль is not None else действие()


def _разобрать(сырая):
    try: запись = json.loads(сырая.decode('utf-8'), object_pairs_hook=_пары, parse_constant=_запрет_числа)
    except (ValueError, UnicodeError, RecursionError) as ошибка: raise ОшибкаВхода('повреждённая законченная строка JSONL') from ошибка
    требовать(type(запись) is dict and type(запись.get('type')) is str and type(запись.get('payload')) is dict, 'повреждённая оболочка JSONL')
    return запись


@contextmanager
def _открыть(путь, предел, наблюдаемая_граница=None):
    путь = Path(путь).absolute()
    требовать(путь == путь.resolve(), 'symlink в источнике')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        до = os.fstat(дескриптор)
        требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1 and до.st_uid == os.getuid(), 'не обычный собственный файл')
        размер = до.st_size if наблюдаемая_граница is None else число(наблюдаемая_граница)
        требовать(0 < размер <= предел and размер <= до.st_size, 'превышен бюджет источника или источник усечён')
        yield дескриптор, размер, [до.st_dev, до.st_ino]
        после = os.fstat(дескриптор); именованный = путь.stat(follow_symlinks=False)
        признаки = lambda данные: (данные.st_dev, данные.st_ino, данные.st_size, данные.st_mtime_ns, данные.st_ctime_ns)
        требовать(признаки(до) == признаки(после) == признаки(именованный) and путь == путь.resolve(), 'источник изменился при наблюдении')
    finally: os.close(дескриптор)


def _строки(дескриптор, размер, профиль):
    """Читать только зафиксированное st_size; ни read(-1), ни погоня за EOF."""
    остаток = размер
    буфер = bytearray()
    смещение = 0
    записей = 0
    while остаток:
        часть = _измерить(профиль, 'чтение', lambda: os.read(дескриптор, min(РАЗМЕР_ЧАНКА, остаток)))
        требовать(bool(часть), 'источник усечён при чтении')
        остаток -= len(часть); буфер.extend(часть)
        начало = 0
        while True:
            конец = буфер.find(b'\n', начало)
            if конец < 0: break
            конец += 1
            требовать(конец - начало <= ПРЕДЕЛ_СТРОКИ, 'превышен бюджет raw-строки')
            сырая = bytes(буфер[начало:конец])
            записей += 1
            требовать(записей <= ПРЕДЕЛ_ЗАПИСЕЙ, 'превышен бюджет записей')
            yield смещение, сырая, True
            смещение += len(сырая); начало = конец
        if начало: del буфер[:начало]
        требовать(len(буфер) <= ПРЕДЕЛ_СТРОКИ, 'превышен бюджет незаконченной raw-строки')
    if буфер: yield смещение, bytes(буфер), False


def проверить_курсор(курсор, задача):
    идентификатор(задача)
    поля(курсор, ('схема', 'идентификатор_задачи', 'хэш_источника', 'граница_байтов', 'хэш_префикса', 'позиции'))
    требовать(курсор['схема'] == СХЕМА_ПОТОКОВОГО_КУРСОРА and курсор['идентификатор_задачи'] == задача, 'чужой потоковый курсор')
    хэш_строка(курсор['хэш_источника']); хэш_строка(курсор['хэш_префикса'])
    требовать(0 < число(курсор['граница_байтов']) <= ПРЕДЕЛ_ПЕРВИЧНОГО_ИСТОЧНИКА, 'недопустимая граница первичного префикса')
    требовать(type(курсор['позиции']) is list and 0 < len(курсор['позиции']) <= ПРЕДЕЛ_ЗАПИСЕЙ, 'неверные позиции')
    предыдущий = 0
    for номер, позиция in enumerate(курсор['позиции'], 1):
        поля(позиция, ('номер', 'начало', 'конец'))
        требовать(число(позиция['номер']) == номер and предыдущий <= число(позиция['начало']) < число(позиция['конец']) <= курсор['граница_байтов'], 'порядок позиций нарушен')
        предыдущий = позиция['конец']
    return курсор


def _состав(сообщение):
    return {поле: сообщение[поле] for поле in ('роль', 'фаза', 'части', 'виды_частей')}


def _виды_ответа(полезное):
    """Читать raw-аннотацию до нормализации; null поля не означает отсутствие."""
    метаданные = полезное.get('internal_chat_message_metadata_passthrough')
    требовать(метаданные is None or type(метаданные) is dict, 'повреждённые метаданные ответа')
    if метаданные is None or 'content_item_kinds' not in метаданные: return None
    виды = метаданные['content_item_kinds']
    требовать(type(виды) is list, 'повреждённая аннотация ответа')
    return виды


def _проверить_части(сообщение):
    роль = сообщение['роль']; части = сообщение['части']; виды = сообщение['виды_частей']; фаза = сообщение['фаза']
    if роль == 'user':
        исходное = {'type': 'message', 'role': роль, 'phase': фаза, 'content': части,
                    'internal_chat_message_metadata_passthrough': {'content_item_kinds': виды}}
        требовать(классифицировать_сообщение(исходное) == сообщение['происхождение'] == 'человек', 'неподтверждённое происхождение частей')
    else:
        требовать(роль == 'assistant' and фаза in ('commentary', 'final', 'final_answer') and сообщение['происхождение'] == 'ответ ассистента', 'неподдержанный ответ')
        требовать(type(части) is list and 0 < len(части) <= 256, 'неверный состав ответа')
        # Внешний ContentItemKind — открытая строка; здесь закрытый поддержанный поднабор.
        требовать(виды is None or (type(виды) is list and len(виды) == len(части) and all(type(вид) is str and вид == 'unknown' for вид in виды)), 'неподдержанная или неполная аннотация ответа')
        for часть in части:
            поля(часть, ('type', 'text'))
            требовать(часть['type'] == 'output_text', 'неизвестная часть ответа')
            строка(часть['text'], пустая=True)


def проверить_экспорт_частей(экспорт, задача):
    идентификатор(задача)
    поля(экспорт, ('схема', 'идентификатор_задачи', 'сообщения'))
    требовать(экспорт['схема'] == СХЕМА_ЭКСПОРТА_ЧАСТЕЙ and экспорт['идентификатор_задачи'] == задача, 'чужой экспорт частей')
    требовать(type(экспорт['сообщения']) is list and 0 < len(экспорт['сообщения']) <= ПРЕДЕЛ_ЗАПИСЕЙ, 'неверное число сообщений')
    объём = 0
    for номер, сообщение in enumerate(экспорт['сообщения'], 1):
        поля(сообщение, ('номер', 'роль', 'фаза', 'части', 'виды_частей', 'происхождение', 'байтовая_длина', 'хэш_частей'))
        требовать(число(сообщение['номер']) == номер, 'нарушен номер сообщения')
        _проверить_части(сообщение)
        байты = кодировать(_состав(сообщение))
        требовать(число(сообщение['байтовая_длина']) == len(байты) and хэш_строка(сообщение['хэш_частей']) == хэш(байты), 'состав частей изменён')
        объём += len(байты)
        требовать(объём <= ПРЕДЕЛ_ЭКСПОРТА, 'превышен бюджет частей')
    требовать(len(кодировать(экспорт)) <= ПРЕДЕЛ_ЭКСПОРТА, 'превышен бюджет экспорта')
    return экспорт['сообщения']


def _выбрать(полезное, номер):
    требовать(type(полезное.get('type')) is str, 'нет типа response_item')
    if полезное['type'] != 'message': return None
    роль = полезное.get('role')
    требовать(роль in ('user', 'assistant', 'system', 'developer', 'tool'), 'неизвестная роль')
    if роль == 'user':
        происхождение = классифицировать_сообщение(полезное)
        требовать(происхождение != 'неоднозначный', 'неоднозначное происхождение raw-сообщения')
        if происхождение != 'человек': return None
        виды = полезное['internal_chat_message_metadata_passthrough']['content_item_kinds']
    elif роль == 'assistant':
        фаза = полезное.get('phase')
        требовать(фаза in ('analysis', 'commentary', 'final', 'final_answer'), 'неизвестная фаза ответа')
        if фаза == 'analysis': return None
        происхождение = 'ответ ассистента'; виды = _виды_ответа(полезное)
    else: return None
    запись = {'номер': номер, 'роль': роль, 'фаза': полезное.get('phase'), 'части': полезное.get('content'), 'виды_частей': виды, 'происхождение': происхождение}
    _проверить_части(запись)
    байты = кодировать(_состав(запись))
    запись.update(байтовая_длина=len(байты), хэш_частей=хэш(байты))
    return запись


def экспортировать_файл(путь, задача, *, квитанция=None, закрепить=False, профиль=None):
    идентификатор(задача)
    if квитанция is not None: проверить_курсор(квитанция, задача)
    требовать(not закрепить or квитанция is not None, 'нет курсора закрепления')
    сообщения = []; позиции = []; хэшер = hashlib.sha256(); источник = None; граница = 0; объём = 0
    прежняя_проверена = квитанция is None
    with _открыть(путь, ПРЕДЕЛ_ПЕРВИЧНОГО_ИСТОЧНИКА, квитанция['граница_байтов'] if закрепить else None) as (дескриптор, размер, _):
        for начало, сырая, закончена in _строки(дескриптор, размер, профиль):
            if not закончена: break
            if закрепить and начало >= квитанция['граница_байтов']: break
            запись = _измерить(профиль, 'разбор_json', lambda: _разобрать(сырая))
            if начало == 0:
                требовать(запись['type'] == 'session_meta' and запись['payload'].get('id') == задача, 'неверная задача JSONL')
                источник = хэш(сырая)
            else: требовать(запись['type'] != 'session_meta', 'повторная идентичность источника')
            _измерить(профиль, 'хэширование', lambda: хэшер.update(сырая))
            граница = начало + len(сырая)
            if запись['type'] == 'response_item':
                сообщение = _измерить(профиль, 'классификация_и_части', lambda: _выбрать(запись['payload'], len(сообщения) + 1))
                if сообщение is not None:
                    объём += len(кодировать(сообщение))
                    требовать(объём <= ПРЕДЕЛ_ЭКСПОРТА, 'превышен бюджет экспорта')
                    сообщения.append(сообщение); позиции.append({'номер': len(сообщения), 'начало': начало, 'конец': граница})
            if квитанция is not None and граница == квитанция['граница_байтов']:
                фактическая = {'схема': СХЕМА_ПОТОКОВОГО_КУРСОРА, 'идентификатор_задачи': задача, 'хэш_источника': источник, 'граница_байтов': граница, 'хэш_префикса': хэшер.hexdigest(), 'позиции': позиции}
                требовать(кодировать(фактическая) == кодировать(квитанция), 'прежний префикс или курсор изменён')
                прежняя_проверена = True
        требовать(прежняя_проверена, 'прежняя граница не найдена')
    экспорт = {'схема': СХЕМА_ЭКСПОРТА_ЧАСТЕЙ, 'идентификатор_задачи': задача, 'сообщения': сообщения}
    _измерить(профиль, 'проверка_экспорта', lambda: проверить_экспорт_частей(экспорт, задача))
    байты = _измерить(профиль, 'кодирование_экспорта', lambda: кодировать(экспорт))
    return байты, {'схема': СХЕМА_ПОТОКОВОГО_КУРСОРА, 'идентификатор_задачи': задача, 'хэш_источника': источник, 'граница_байтов': граница, 'хэш_префикса': хэшер.hexdigest(), 'позиции': позиции}


def прочитать_хвост(путь, задача, курсор, *, предел_хвоста=64 * 1024 * 1024, профиль=None):
    """База повторно хэшируется; в память возвращается только наблюдённый late raw."""
    проверить_курсор(курсор, задача); число(предел_хвоста)
    база = курсор['граница_байтов']; хэшер = hashlib.sha256(); хвост = bytearray(); проверена = False
    with _открыть(путь, база + предел_хвоста) as (дескриптор, размер, узел):
        требовать(размер >= база, 'источник усечён до закреплённой границы')
        for начало, сырая, закончена in _строки(дескриптор, размер, профиль):
            if начало == 0:
                требовать(закончена, 'нет session_meta')
                запись = _измерить(профиль, 'разбор_json', lambda: _разобрать(сырая))
                требовать(запись['type'] == 'session_meta' and запись['payload'].get('id') == задача and хэш(сырая) == курсор['хэш_источника'], 'источник подменён')
            if начало < база:
                требовать(закончена and начало + len(сырая) <= база, 'граница не завершена LF')
                _измерить(профиль, 'хэширование', lambda: хэшер.update(сырая))
                if начало + len(сырая) == база:
                    требовать(хэшер.hexdigest() == курсор['хэш_префикса'], 'старые байты изменены')
                    проверена = True
            else: хвост.extend(сырая)
        требовать(проверена and len(хвост) <= предел_хвоста, 'неполное наблюдение или переполненный поздний хвост')
    return bytes(хвост), узел

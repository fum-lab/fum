"""Законченный префикс JSONL Codex; очередь доставки и отмена не реализованы."""
import json

from канон import ОшибкаВхода, _пары, кодировать, требовать, поля, число, строка, идентификатор, хэш, хэш_строка


СХЕМА_ЭКСПОРТА = 'fum.экспорт-команд.1'
СХЕМА_КУРСОРА = 'fum.локальная-граница-диалога.1'


def проверить_экспорт(экспорт, задача):
    поля(экспорт, ('схема', 'идентификатор_задачи', 'сообщения'))
    требовать(экспорт['схема'] == СХЕМА_ЭКСПОРТА and экспорт['идентификатор_задачи'] == задача, 'чужой экспорт')
    требовать(type(экспорт['сообщения']) is list and экспорт['сообщения'], 'пустой экспорт')
    for номер, сообщение in enumerate(экспорт['сообщения'], 1):
        поля(сообщение, ('номер', 'роль', 'текст', 'байтовая_длина', 'хэш_байтов'))
        требовать(число(сообщение['номер']) == номер, 'пропуск или перестановка номера')
        требовать(сообщение['роль'] in ('user', 'assistant'), 'непубликуемая роль')
        текст = строка(сообщение['текст']).encode('utf-8')
        требовать(число(сообщение['байтовая_длина']) == len(текст) and хэш_строка(сообщение['хэш_байтов']) == хэш(текст), 'байты сообщения не совпадают')
    return экспорт['сообщения']


def экспортировать(данные, задача, *, квитанция=None, закрепить=False):
    """Номера назначаются видимым сообщениям response_item; event_msg не дублирует их.

    Локальная квитанция не публикуется. Источник — UUID session_meta и хэш первой
    строки, а не изменчивый локальный путь. Новая граница пересчитывает весь префикс.
    """
    идентификатор(задача)
    граница = данные.rfind(b'\n') + 1
    if квитанция is not None:
        поля(квитанция, ('схема', 'идентификатор_задачи', 'хэш_источника', 'граница_байтов', 'хэш_префикса', 'позиции'))
        требовать(квитанция['схема'] == СХЕМА_КУРСОРА and квитанция['идентификатор_задачи'] == задача, 'чужая квитанция')
        прежняя = число(квитанция['граница_байтов'])
        требовать(0 < прежняя <= граница and данные[прежняя - 1:прежняя] == b'\n', 'граница не завершена')
        требовать(хэш(данные[:прежняя]) == хэш_строка(квитанция['хэш_префикса']), 'прочитанный префикс изменён')
        # Сверяем весь прежний курсор, включая позиции и идентичность источника.
        _, фактическая = экспортировать(данные[:прежняя], задача)
        требовать(кодировать(квитанция) == кодировать(фактическая), 'курсор не соответствует источнику')
        if закрепить:
            граница = прежняя
    else:
        требовать(not закрепить, 'закрепление требует прежнего курсора')
    сообщения = []
    позиции = []
    смещение = 0
    источник = None
    for часть_строки in данные[:граница].split(b'\n')[:-1]:
        сырая = часть_строки + b'\n'
        try:
            запись = json.loads(сырая.decode('utf-8'), object_pairs_hook=_пары)
        except (ValueError, UnicodeError, RecursionError) as ошибка:
            raise ОшибкаВхода('повреждённая законченная строка JSONL') from ошибка
        требовать(type(запись) is dict, 'строка JSONL не объект')
        данные_записи = запись.get('payload')
        if смещение == 0:
            требовать(запись.get('type') == 'session_meta' and type(данные_записи) is dict and данные_записи.get('id') == задача, 'неверный источник диалога')
            источник = хэш(сырая)
        else:
            требовать(запись.get('type') != 'session_meta', 'повторная идентичность источника')
        if запись.get('type') == 'response_item' and type(данные_записи) is dict and данные_записи.get('type') == 'message':
            роль = данные_записи.get('role')
            включить = False
            if роль == 'user':
                мета = данные_записи.get('internal_chat_message_metadata_passthrough')
                требовать(type(мета) is dict and type(мета.get('content_item_kinds')) is list, 'неизвестное происхождение user message')
                виды = мета['content_item_kinds']
                включить = 'user.text' in виды
                if not включить:
                    внутренние = ('plugins.recommendations', 'agents_md.instructions', 'environments.environment_context')
                    требовать(bool(виды) and all(вид in внутренние for вид in виды), 'неизвестный вид пользовательского сообщения')
                if включить:
                    требовать(виды == ['user.text'], 'мультимодальная или составная команда требует отдельного экспорта')
            elif роль == 'assistant':
                фаза = данные_записи.get('phase')
                требовать(фаза in ('commentary', 'final', 'final_answer', 'analysis'), 'неизвестная фаза ответа')
                включить = фаза != 'analysis'
            if включить:
                части = данные_записи.get('content')
                требовать(type(части) is list and len(части) == 1 and type(части[0]) is dict, 'неподдержанный состав сообщения')
                требовать(части[0].get('type') == ('input_text' if роль == 'user' else 'output_text'), 'неизвестная текстовая часть')
                текст = строка(части[0].get('text'))
                номер = len(сообщения) + 1
                сообщения.append({'номер': номер, 'роль': роль, 'текст': текст, 'байтовая_длина': len(текст.encode()), 'хэш_байтов': хэш(текст.encode())})
                позиции.append({'номер': номер, 'начало': смещение, 'конец': смещение + len(сырая)})
        смещение += len(сырая)
    экспорт = {'схема': СХЕМА_ЭКСПОРТА, 'идентификатор_задачи': задача, 'сообщения': сообщения}
    проверить_экспорт(экспорт, задача)
    return кодировать(экспорт), {'схема': СХЕМА_КУРСОРА, 'идентификатор_задачи': задача, 'хэш_источника': источник,
                               'граница_байтов': граница, 'хэш_префикса': хэш(данные[:граница]), 'позиции': позиции}

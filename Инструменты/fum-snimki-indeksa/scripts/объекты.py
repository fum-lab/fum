"""Сырые Git-объекты; подготовка индекса является отдельной мутацией."""
import hashlib
import os
import re
import subprocess
import unicodedata
from pathlib import Path

from канон import ОшибкаВхода, требовать, поля, число, строка, хэш, хэш_строка


ЗАРЕЗЕРВИРОВАНО = '.fum-приёмка'


def путь(значение):
    строка(значение)
    части = значение.split('/')
    требовать(all(часть and часть not in ('.', '..') for часть in части), 'неканонический путь')
    требовать(not any(ord(знак) < 32 or знак in '\\:\x7f' for знак in значение), 'небезопасный путь')
    требовать(all(часть.casefold() != '.git' for часть in части), 'служебный путь Git')
    требовать(unicodedata.normalize('NFC', части[0]).casefold() != ЗАРЕЗЕРВИРОВАНО.casefold(), 'обратная зависимость от записи входа')
    return значение


class ОбъектыГит:
    def __init__(self, корень):
        self.корень = Path(корень).absolute()
        требовать(self.корень == self.корень.resolve(), 'символическая ссылка в корне')
        self.среда = {ключ: значение for ключ, значение in os.environ.items() if not ключ.startswith('GIT_')}
        self.среда.update(GIT_NO_REPLACE_OBJECTS='1', GIT_NO_LAZY_FETCH='1', GIT_OPTIONAL_LOCKS='0',
                         GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull, GIT_TERMINAL_PROMPT='0')
        вершина = Path(self.гит('rev-parse', '--show-toplevel').decode().strip()).resolve()
        требовать(вершина == self.корень, 'требуется точный физический корень checkout')
        self.алгоритм = self.гит('rev-parse', '--show-object-format').decode().strip()
        требовать(self.алгоритм in ('sha1', 'sha256'), 'неподдержанный формат Git')
        self.длина_оид = 40 if self.алгоритм == 'sha1' else 64
        self.чтения = 0
        self.объём = 0
        self.кэш = {}
        self.объём_кэша = 0
        self.переиспользования = 0

    def гит(self, *аргументы, вход=None):
        try:
            результат = subprocess.run(['git', '-c', 'protocol.allow=never', '-c', 'core.fsmonitor=false',
                                        '-C', str(self.корень), *аргументы], input=вход,
                                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=self.среда, timeout=30)
        except (OSError, subprocess.TimeoutExpired) as ошибка:
            raise ОшибкаВхода('Git недоступен или превышен предел времени') from ошибка
        требовать(результат.returncode == 0, 'Git отказал: ' + аргументы[0])
        return результат.stdout

    def оид(self, значение):
        return {'алгоритм': self.алгоритм, 'значение': значение}

    def проверить_оид(self, объект):
        поля(объект, ('алгоритм', 'значение'))
        требовать(объект['алгоритм'] == self.алгоритм, 'алгоритм OID не совпадает с репозиторием')
        требовать(type(объект['значение']) is str and re.fullmatch('[0-9a-f]{' + str(self.длина_оид) + '}', объект['значение']) is not None, 'неполный OID')
        return объект['значение']

    def прочитать(self, объект, тип):
        значение = self.проверить_оид(объект)
        требовать(тип in ('blob', 'tree', 'commit'), 'неподдержанный тип объекта')
        ключ = (значение, тип)
        if ключ in self.кэш:
            self.переиспользования += 1
            return self.кэш[ключ]
        ответ = self.гит('cat-file', '--batch', вход=(значение + '\n').encode('ascii'))
        заголовок, разделитель, остаток = ответ.partition(b'\n')
        части = заголовок.split(b' ')
        требовать(разделитель and len(части) == 3, 'объект отсутствует')
        требовать(части[0] == значение.encode() and части[1] == тип.encode(), 'неверный OID или тип объекта')
        требовать(re.fullmatch(b'0|[1-9][0-9]*', части[2]) is not None, 'неверная длина объекта')
        длина = int(части[2])
        требовать(len(остаток) == длина + 1 and остаток[-1:] == b'\n', 'объект прочитан не полностью')
        байты = остаток[:-1]
        вычисленный = hashlib.new(self.алгоритм, тип.encode() + b' ' + str(длина).encode() + b'\0' + байты).hexdigest()
        требовать(вычисленный == значение, 'сырые байты не соответствуют OID')
        self.чтения += 1
        self.объём += длина
        # Только независимо проверенные байты полного OID, на жизнь этого читателя.
        if self.объём_кэша + длина <= 64 * 1024 * 1024 and len(self.кэш) < 10000:
            self.кэш[ключ] = байты
            self.объём_кэша += длина
        return байты

    def дерево_коммита(self, объект):
        байты = self.прочитать(объект, 'commit')
        первая = байты.partition(b'\n')[0]
        требовать(первая.startswith(b'tree '), 'commit не содержит tree')
        try:
            дерево = self.оид(первая[5:].decode('ascii'))
        except UnicodeError as ошибка:
            raise ОшибкаВхода('неверный tree commit') from ошибка
        self.проверить_оид(дерево)
        self.прочитать(дерево, 'tree')
        return дерево

    def дерево(self, объект):
        результат = {}
        имена = set()

        def обойти(корень, префикс, глубина):
            требовать(глубина <= 64, 'слишком глубокое дерево')
            данные = self.прочитать(корень, 'tree')
            позиция = 0
            прежний = None
            while позиция < len(данные):
                пробел = данные.find(b' ', позиция)
                нуль = данные.find(b'\0', пробел + 1)
                конец = нуль + 1 + self.длина_оид // 2
                требовать(пробел > позиция and нуль > пробел and конец <= len(данные), 'повреждённый tree')
                режим = данные[позиция:пробел]
                имя = данные[пробел + 1:нуль]
                требовать(режим in (b'40000', b'100644', b'100755', b'160000'), 'неподдержанный режим, включая symlink')
                требовать(b'/' not in имя, 'разделитель внутри имени tree')
                ключ = имя + (b'/' if режим == b'40000' else b'')
                требовать(прежний is None or прежний < ключ, 'неканонический порядок tree')
                прежний = ключ
                try:
                    полный = путь(префикс + имя.decode('utf-8'))
                except UnicodeError as ошибка:
                    raise ОшибкаВхода('имя tree не является UTF-8') from ошибка
                сопоставление = unicodedata.normalize('NFC', полный).casefold()
                требовать(сопоставление not in имена, 'коллизия имён tree')
                имена.add(сопоставление)
                дочерний = self.оид(данные[нуль + 1:конец].hex())
                if режим == b'40000':
                    обойти(дочерний, полный + '/', глубина + 1)
                else:
                    результат[полный] = {'объект': дочерний, 'режим': режим.decode('ascii')}
                позиция = конец
        обойти(объект, '', 0)
        return результат

    def ссылка(self, дерево, имя, инвентарь=None):
        путь(имя)
        листья = self.дерево(дерево) if инвентарь is None else инвентарь
        требовать(имя in листья, 'путь отсутствует в закреплённом дереве')
        лист = листья[имя]
        требовать(лист['режим'] in ('100644', '100755'), 'gitlink не является blob')
        байты = self.прочитать(лист['объект'], 'blob')
        return {'путь': имя, 'объект': лист['объект'], 'длина': len(байты), 'хэш_байтов': хэш(байты)}

    def проверить_ссылку(self, дерево, ссылка, инвентарь=None):
        поля(ссылка, ('путь', 'объект', 'длина', 'хэш_байтов'))
        число(ссылка['длина'])
        хэш_строка(ссылка['хэш_байтов'])
        self.проверить_оид(ссылка['объект'])
        фактическая = self.ссылка(дерево, ссылка['путь'], инвентарь)
        требовать(фактическая == ссылка, 'ссылка не совпадает с сырыми байтами tree')
        return self.прочитать(ссылка['объект'], 'blob')

    def наблюдать(self, коммит, ветка):
        значение = self.проверить_оид(коммит)
        требовать(type(ветка) is str and ветка.startswith('refs/heads/'), 'требуется полный ref ветки')
        self.гит('check-ref-format', ветка)
        требовать(self.гит('symbolic-ref', 'HEAD').decode().strip() == ветка, 'ожидаемая ветка не совпадает')
        требовать(self.гит('rev-parse', '--verify', 'HEAD').decode().strip() == значение, 'ожидаемый HEAD не совпадает')
        self.дерево_коммита(коммит)


def подготовить_дерево(корень, ожидаемый_коммит, ожидаемая_ветка):
    """Пишет tree-объекты и может обновить cache-tree индекса. Не является чистым чтением или допуском."""
    объекты = ОбъектыГит(корень)
    объекты.наблюдать(ожидаемый_коммит, ожидаемая_ветка)
    требовать(not объекты.гит('ls-files', '--unmerged', '-z'), 'конфликт индекса')
    дерево = объекты.оид(объекты.гит('write-tree').decode().strip())
    объекты.дерево(дерево)
    объекты.наблюдать(ожидаемый_коммит, ожидаемая_ветка)
    return дерево

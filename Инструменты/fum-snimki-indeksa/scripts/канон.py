"""Единственное кодирование входа; независимо от форматов run-v4/report-v3."""
import hashlib
import json
import re
import uuid


class ОшибкаВхода(ValueError):
    """Вход не подтверждён; исполнение запрещено."""


def требовать(условие, причина):
    if not условие:
        raise ОшибкаВхода(причина)


def поля(значение, имена):
    требовать(type(значение) is dict and set(значение) == set(имена), 'неверный закрытый набор полей')


def число(значение):
    требовать(type(значение) is int and 0 <= значение <= 2**63 - 1, 'недопустимое целое число')
    return значение


def строка(значение, пустая=False):
    требовать(type(значение) is str and (пустая or bool(значение)), 'ожидалась строка')
    требовать(not any(0xD800 <= ord(знак) <= 0xDFFF for знак in значение), 'суррогат Unicode')
    return значение


def идентификатор(значение):
    строка(значение)
    try:
        требовать(str(uuid.UUID(значение)) == значение, 'неканонический UUID')
    except ValueError as ошибка:
        raise ОшибкаВхода('неканонический UUID') from ошибка
    return значение


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def хэш_строка(значение):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение) is not None, 'неверный SHA-256')
    return значение


def _кавычки(значение):
    строка(значение, пустая=True)
    return '"' + ''.join('\\' + знак if знак in ('"', '\\') else f'\\u{ord(знак):04x}' if ord(знак) < 32 else знак for знак in значение) + '"'


def _текст(значение):
    if значение is None:
        return 'null'
    if type(значение) is bool:
        return 'true' if значение else 'false'
    if type(значение) is int:
        return str(число(значение))
    if type(значение) is str:
        return _кавычки(значение)
    if type(значение) is list:
        return '[' + ','.join(_текст(часть) for часть in значение) + ']'
    if type(значение) is dict:
        for ключ in значение:
            строка(ключ, пустая=True)
        return '{' + ','.join(_кавычки(ключ) + ':' + _текст(значение[ключ]) for ключ in sorted(значение)) + '}'
    raise ОшибкаВхода('тип не входит в канонический JSON')


def кодировать(значение):
    try:
        return (_текст(значение) + '\n').encode('utf-8')
    except (RecursionError, UnicodeError) as ошибка:
        raise ОшибкаВхода('недопустимая структура JSON') from ошибка


def _пары(пары):
    результат = {}
    for ключ, значение in пары:
        требовать(ключ not in результат, 'повторный ключ JSON')
        результат[ключ] = значение
    return результат


def _запрет_числа(значение):
    raise ОшибкаВхода('нецелое или специальное число JSON')


def разобрать(байты):
    try:
        return json.loads(байты.decode('utf-8'), object_pairs_hook=_пары, parse_float=_запрет_числа, parse_constant=_запрет_числа)
    except (ValueError, UnicodeError, RecursionError) as ошибка:
        raise ОшибкаВхода('недопустимый JSON') from ошибка


def прочитать(байты):
    значение = разобрать(байты)
    требовать(кодировать(значение) == байты, 'неканонические байты JSON')
    return значение


def конверт(байты):
    return {'алгоритм': 'sha256', 'длина': len(байты), 'хэш_байтов': хэш(байты)}


def проверить_конверт(байты, оболочка):
    описание = прочитать(оболочка)
    поля(описание, ('алгоритм', 'длина', 'хэш_байтов'))
    число(описание['длина'])
    хэш_строка(описание['хэш_байтов'])
    требовать(описание == конверт(байты), 'длина или хэш конверта не совпадают')
    return прочитать(байты)

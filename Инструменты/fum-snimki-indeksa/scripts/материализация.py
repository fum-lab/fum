@contextmanager
def _каталог(имя):
    """Пройти каждый компонент без symlink; держать конечный каталог открытым."""
    имя = Path(имя).absolute()
    требовать(имя == имя.resolve(), 'нужен физический путь без символических ссылок')
    дескриптор = os.open('/', os.O_RDONLY | os.O_DIRECTORY)
    try:
        for часть in имя.parts[1:]:
            новый = os.open(часть, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=дескриптор)
            os.close(дескриптор)
            дескриптор = новый
        yield дескриптор
    finally:
        os.close(дескриптор)


def _идентичность(дескриптор):
    состояние = os.fstat(дескриптор)
    return {'устройство': состояние.st_dev, 'инод': состояние.st_ino}


def _привязка(имя, дескриптор):
    with _каталог(имя) as повторный:
        требовать(_идентичность(повторный) == _идентичность(дескриптор), 'подмена именованного каталога')


def _частный(дескриптор):
    состояние = os.fstat(дескриптор)
    требовать(состояние.st_uid == os.getuid() and stat.S_IMODE(состояние.st_mode) == 0o700, 'каталог должен принадлежать исполнителю и иметь частный режим 0700')


def _существует(родитель, имя):
    try:
        return os.stat(имя, dir_fd=родитель, follow_symlinks=False)
    except FileNotFoundError:
        return None


def _запись(дескриптор, байты):
    # Короткая запись — наблюдаемый неполный результат, а не успешный файл.
    for начало in range(0, len(байты), 1024 * 1024):
        кусок = байты[начало:начало + 1024 * 1024]
        требовать(os.write(дескриптор, кусок) == len(кусок), 'короткая запись')


def _синхронизация(дескриптор, профиль):
    with профиль.стадия('fsync'):
        os.fsync(дескриптор)


def _создать_файл(родитель, имя, байты, режим, профиль):
    дескриптор = os.open(имя, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=родитель)
    try:
        _запись(дескриптор, байты)
        os.fchmod(дескриптор, режим)
        _синхронизация(дескриптор, профиль)
        return _идентичность(дескриптор)
    finally:
        os.close(дескриптор)


def _удалить_свой(родитель, имя, идентичность):
    состояние = _существует(родитель, имя)
    требовать(состояние is not None and {'устройство': состояние.st_dev, 'инод': состояние.st_ino} == идентичность, 'подмена служебного файла')
    os.unlink(имя, dir_fd=родитель)


def _защищённые(читатель):
    корни = [читатель.корень]
    for аргументы in (('--absolute-git-dir',), ('--path-format=absolute', '--git-common-dir'), ('--path-format=absolute', '--git-path', 'objects')):
        корни.append(Path(читатель.гит('rev-parse', *аргументы).decode().strip()).resolve())
    альтернаты = корни[-1] / 'info/alternates'
    требовать(not альтернаты.exists(), 'внешние alternates не поддержаны материализацией')
    return корни


def _ожидание(корень, байты, оболочка, ожидаемый_коммит, ожидаемая_ветка, реестр, локальные_зависимости, профиль):
    проверить_вход(корень, байты, оболочка, ожидаемый_коммит=ожидаемый_коммит, ожидаемая_ветка=ожидаемая_ветка,
                  реестр=реестр, локальные_зависимости=локальные_зависимости, профиль=профиль)
    требовать(реестр.проверить(байты).is_file(), 'вход должен быть ранее зарегистрирован в доверенном реестре')
    запись = прочитать(байты)
    источники = {}
    каталоги = set()
    читатели = []
    защищённые = [реестр.каталог]
    with профиль.стадия('чтение_git'):
        def добавить(читатель, дерево, префикс):
            читатели.append(читатель)
            защищённые.extend(_защищённые(читатель))
            вложенные = []
            листья = читатель.дерево(дерево, каталоги=вложенные)
            каталоги.update(префикс + имя for имя in вложенные)
            for имя, лист in листья.items():
                if лист['режим'] == '160000':
                    требовать(not префикс, 'вложенный gitlink не поддержан')
                    каталоги.add(имя)
                    continue
                полный = путь(префикс + имя)
                требовать(полный not in источники, 'коллизия материализованных файлов')
                сырые = читатель.прочитать(лист['объект'], 'blob')
                описание = {'путь': полный, 'режим': лист['режим'], 'длина': len(сырые), 'хэш_байтов': хэш(сырые)}
                источники[полный] = (читатель, лист['объект'], описание)
        добавить(ОбъектыГит(корень, профиль=профиль), запись['дерево_входа'], '')
        for зависимость in запись['зависимости']:
            if зависимость['вид'] == 'gitlink':
                добавить(ОбъектыГит(локальные_зависимости[зависимость['путь']], профиль=профиль), зависимость['дерево'], зависимость['путь'] + '/')
    профиль.измерения.append({'стадия': 'ожидание', 'чтения_git': sum(читатель.чтения for читатель in читатели),
        'байты_git': sum(читатель.объём for читатель in читатели), 'байты_кэша': sum(читатель.объём_кэша for читатель in читатели),
        'файлы': len(источники), 'байты_файлов': sum(источник[2]['длина'] for источник in источники.values())})
    return запись, источники, sorted(каталоги, key=lambda имя: имя.encode()), защищённые


def _граница(назначение, квитанция, защищённые):
    назначение = Path(назначение).absolute()
    квитанция = Path(квитанция).absolute()
    требовать(назначение == назначение.resolve() and квитанция == квитанция.resolve(), 'symlink в назначении или квитанции')
    требовать(назначение.parent == квитанция.parent, 'квитанция должна быть соседним локальным файлом вне назначения')
    ожидание = квитанция.name + '.незавершено'
    требовать(len({назначение.name, квитанция.name, ожидание}) == 3, 'совпадение служебных путей')
    for имя in (назначение.name, квитанция.name, ожидание): путь(имя)
    for кандидат in (назначение, квитанция, квитанция.parent / ожидание):
        предки = [предок for предок in (кандидат, *кандидат.parents) if предок.exists()]
        for корень in защищённые:
            if корень.exists():
                требовать(not any(os.path.samefile(предок, корень) for предок in предки), 'алиас защищённого каталога')
            if кандидат.exists():
                требовать(not any(os.path.samefile(кандидат, предок) for предок in (корень, *корень.parents) if предок.exists()), 'назначение охватывает защищённый каталог')
        for корень in защищённые:
            требовать(not кандидат.is_relative_to(корень) and not корень.is_relative_to(кандидат), 'назначение пересекает источник, реестр или хранилище Git')
    for предок in (назначение.parent, *назначение.parent.parents):
        требовать(not (предок / '.git').exists() and not (предок / '.git').is_symlink(), 'назначение внутри другого checkout')
        требовать(not ((предок / 'HEAD').exists() and (предок / 'objects').exists() and (предок / 'refs').exists()), 'назначение внутри bare Git')
    return назначение, квитанция, ожидание


@contextmanager
def _подкаталог(корень, части):
    дескриптор = os.dup(корень)
    try:
        for часть in части:
            новый = os.open(часть, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=дескриптор)
            os.close(дескриптор)
            дескриптор = новый
        yield дескриптор
    finally:
        os.close(дескриптор)


def _сверить(дескриптор, ожидаемые, ожидаемые_каталоги, профиль):
    """Самостоятельный обход диска; не использует буферы писателя и квитанцию."""
    фактические = []
    каталоги = []
    иноды = set()
    объём = 0
    with профиль.стадия('независимая_сверка'):
        def обойти(каталог, префикс):
            nonlocal объём
            _частный(каталог)
            состояние_каталога = os.fstat(каталог)
            имена = sorted(os.listdir(каталог), key=lambda имя: имя.encode())
            for имя in имена:
                полный = путь(префикс + имя)
                до = os.stat(имя, dir_fd=каталог, follow_symlinks=False)
                if stat.S_ISDIR(до.st_mode):
                    каталоги.append(полный)
                    with _подкаталог(каталог, [имя]) as дочерний:
                        требовать((до.st_dev, до.st_ino) == (os.fstat(дочерний).st_dev, os.fstat(дочерний).st_ino), 'подмена каталога при обходе')
                        обойти(дочерний, полный + '/')
                        после = os.stat(имя, dir_fd=каталог, follow_symlinks=False)
                        требовать(stat.S_ISDIR(после.st_mode) and (после.st_dev, после.st_ino) == (до.st_dev, до.st_ino), 'именованный каталог заменён')
                else:
                    требовать(stat.S_ISREG(до.st_mode), 'необычный файл материализации')
                    файл = os.open(имя, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=каталог)
                    try:
                        начало = os.fstat(файл)
                        требовать(stat.S_ISREG(начало.st_mode) and начало.st_uid == os.getuid() and начало.st_nlink == 1, 'необычный, чужой или связанный файл')
                        пара = (начало.st_dev, начало.st_ino)
                        требовать(пара == (до.st_dev, до.st_ino) and пара not in иноды, 'подмена или повтор inode')
                        иноды.add(пара)
                        режим = stat.S_IMODE(начало.st_mode)
                        требовать(режим in (0o644, 0o755), 'неверный режим файла')
                        размер = 0; свёртка = hashlib.sha256()
                        while кусок := os.read(файл, 1024 * 1024):
                            размер += len(кусок); свёртка.update(кусок)
                        конец = os.fstat(файл)
                        требовать((начало.st_size, начало.st_mtime_ns, начало.st_ctime_ns, начало.st_mode, начало.st_nlink) ==
                                  (конец.st_size, конец.st_mtime_ns, конец.st_ctime_ns, конец.st_mode, конец.st_nlink) and размер == конец.st_size, 'файл менялся при чтении')
                        именованный = os.stat(имя, dir_fd=каталог, follow_symlinks=False)
                        требовать((именованный.st_dev, именованный.st_ino, именованный.st_mode, именованный.st_nlink, именованный.st_size, именованный.st_mtime_ns, именованный.st_ctime_ns) ==
                                  (конец.st_dev, конец.st_ino, конец.st_mode, конец.st_nlink, конец.st_size, конец.st_mtime_ns, конец.st_ctime_ns), 'именованный файл заменён')
                        объём += размер
                        фактические.append({'путь': полный, 'режим': '100755' if режим == 0o755 else '100644', 'длина': размер, 'хэш_байтов': свёртка.hexdigest()})
                    finally:
                        os.close(файл)
            после_обхода = os.fstat(каталог)
            требовать(имена == sorted(os.listdir(каталог), key=lambda имя: имя.encode()) and
                      (состояние_каталога.st_mtime_ns, состояние_каталога.st_ctime_ns) == (после_обхода.st_mtime_ns, после_обхода.st_ctime_ns), 'каталог менялся во время обхода')
        обойти(дескриптор, '')
        фактические.sort(key=lambda файл: файл['путь'].encode())
        требовать(фактические == ожидаемые and sorted(каталоги, key=lambda имя: имя.encode()) == ожидаемые_каталоги, 'фактическое дерево не совпадает с закреплёнными файлами')
    профиль.измерения.append({'стадия': 'сверка', 'чтения_файлов': len(фактические), 'байты_файлов': объём})
    return фактические


def _содержимое_квитанции(запись, байты, назначение, дескриптор, файлы, каталоги):
    привязка = {'хэш_входа': хэш(байты), 'назначение': str(назначение), 'каталог': _идентичность(дескриптор)}
    номер = str(uuid.uuid5(uuid.NAMESPACE_URL, кодировать(привязка).decode('utf-8')))
    return {'схема': 'fum.материализация-снимка.1', 'идентификатор_материализации': номер,
            'идентификатор_задачи': запись['идентификатор_задачи'], 'идентификатор_раунда': запись['идентификатор_раунда'],
            'хэш_входа': хэш(байты), 'дерево_входа': запись['дерево_входа'], 'назначение': str(назначение),
            'идентичность_каталога': _идентичность(дескриптор), 'файлы': файлы, 'каталоги': каталоги,
            'исполнение_разрешено': False, 'коммит_разрешён': False}


def _прочитать_квитанцию(родитель, имя):
    дескриптор = os.open(имя, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=родитель)
    try:
        состояние = os.fstat(дескриптор)
        требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_uid == os.getuid() and состояние.st_nlink == 1 and stat.S_IMODE(состояние.st_mode) == 0o600, 'необычная квитанция')
        with os.fdopen(os.dup(дескриптор), 'rb') as поток:
            return поток.read()
    finally:
        os.close(дескриптор)


def проверить_материализацию(корень, байты, оболочка, *, ожидаемый_коммит, ожидаемая_ветка, реестр,
                             назначение, квитанция, локальные_зависимости=None, профиль=None):
    профиль = профиль if профиль is not None else Профиль()
    запись, источники, каталоги, защищённые = _ожидание(корень, байты, оболочка, ожидаемый_коммит, ожидаемая_ветка, реестр, локальные_зависимости or {}, профиль)
    назначение, квитанция, ожидание = _граница(назначение, квитанция, защищённые)
    with _каталог(назначение.parent) as родитель:
        _частный(родитель)
        требовать(_существует(родитель, ожидание) is None, 'незавершённая материализация')
        сырые = _прочитать_квитанцию(родитель, квитанция.name)
        кандидат = прочитать(сырые)
        требовать(type(кандидат) is dict and 'идентификатор_материализации' in кандидат, 'неверная квитанция')
        with _подкаталог(родитель, [назначение.name]) as дерево:
            файлы = _сверить(дерево, [источники[имя][2] for имя in sorted(источники, key=lambda имя: имя.encode())], каталоги, профиль)
            ожидаемая = _содержимое_квитанции(запись, байты, назначение, дерево, файлы, каталоги)
            требовать(сырые == кодировать(ожидаемая), 'чужая или изменённая квитанция')
            _привязка(назначение, дерево)
        _привязка(назначение.parent, родитель)
        требовать(_существует(родитель, ожидание) is None and _прочитать_квитанцию(родитель, квитанция.name) == сырые, 'квитанция менялась при проверке')
        return ожидаемая


def материализовать(корень, байты, оболочка, *, ожидаемый_коммит, ожидаемая_ветка, реестр,
                    назначение, квитанция, локальные_зависимости=None, профиль=None):
    профиль = профиль if профиль is not None else Профиль()
    зависимости = локальные_зависимости or {}
    запись, источники, каталоги, защищённые = _ожидание(корень, байты, оболочка, ожидаемый_коммит, ожидаемая_ветка, реестр, зависимости, профиль)
    назначение, квитанция, ожидание = _граница(назначение, квитанция, защищённые)
    with _каталог(назначение.parent) as родитель:
        _частный(родитель)
        требовать(_существует(родитель, ожидание) is None, 'осталась незавершённая материализация')
        if _существует(родитель, назначение.name) is not None or _существует(родитель, квитанция.name) is not None:
            требовать(_существует(родитель, назначение.name) is not None and _существует(родитель, квитанция.name) is not None, 'чужое или частичное назначение')
            return проверить_материализацию(корень, байты, оболочка, ожидаемый_коммит=ожидаемый_коммит, ожидаемая_ветка=ожидаемая_ветка,
                реестр=реестр, назначение=назначение, квитанция=квитанция, локальные_зависимости=зависимости, профиль=профиль)
        номер = str(uuid.uuid4())
        отметка = _создать_файл(родитель, ожидание, кодировать({'материализация': номер}), 0o600, профиль)
        _синхронизация(родитель, профиль)
        _привязка(назначение.parent, родитель)
        os.mkdir(назначение.name, 0o700, dir_fd=родитель)
        with _подкаталог(родитель, [назначение.name]) as дерево:
            _привязка(назначение, дерево)
            with профиль.стадия('создание'):
                for имя in sorted(каталоги, key=lambda имя: (имя.count('/'), имя.encode())):
                    части = имя.split('/')
                    with _подкаталог(дерево, части[:-1]) as каталог:
                        os.mkdir(части[-1], 0o700, dir_fd=каталог)
                for имя in sorted(источники, key=lambda имя: имя.encode()):
                    читатель, объект, описание = источники[имя]
                    части = имя.split('/')
                    with _подкаталог(дерево, части[:-1]) as каталог:
                        _создать_файл(каталог, части[-1], читатель.прочитать(объект, 'blob'), int(описание['режим'][-3:], 8), профиль)
                for имя in sorted(каталоги, key=lambda имя: (-имя.count('/'), имя.encode())):
                    with _подкаталог(дерево, имя.split('/')) as каталог: _синхронизация(каталог, профиль)
                _синхронизация(дерево, профиль)
                _синхронизация(родитель, профиль)
            # Новый читатель и повторная полная проверка источника: кэш писателя не является доказательством.
            del источники
            запись, свежие, каталоги, _ = _ожидание(корень, байты, оболочка, ожидаемый_коммит, ожидаемая_ветка, реестр, зависимости, профиль)
            файлы = _сверить(дерево, [свежие[имя][2] for имя in sorted(свежие, key=lambda имя: имя.encode())], каталоги, профиль)
            _привязка(назначение, дерево)
            _привязка(назначение.parent, родитель)
            результат = _содержимое_квитанции(запись, байты, назначение, дерево, файлы, каталоги)
            временное = квитанция.name + '.' + номер + '.подготовка'
            свой = _создать_файл(родитель, временное, кодировать(результат), 0o600, профиль)
            try:
                os.link(временное, квитанция.name, src_dir_fd=родитель, dst_dir_fd=родитель, follow_symlinks=False)
                _удалить_свой(родитель, временное, свой)
                _синхронизация(родитель, профиль)
                _удалить_свой(родитель, ожидание, отметка)
                try:
                    _синхронизация(родитель, профиль)
                    _привязка(назначение, дерево)
                    _привязка(назначение.parent, родитель)
                except BaseException:
                    # Отказ восстановления тоже не превращается в успешный возврат.
                    try: _создать_файл(родитель, ожидание, кодировать({'материализация': номер}), 0o600, профиль)
                    except OSError: pass
                    raise
            finally:
                if _существует(родитель, временное) is not None:
                    _удалить_свой(родитель, временное, свой)
            return результат

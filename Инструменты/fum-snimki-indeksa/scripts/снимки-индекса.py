#!/usr/bin/env python3
"""CLI первого сегмента: подготовка объектов и проверка отделены от допуска."""
import sys
sys.dont_write_bytecode = True

import argparse
from pathlib import Path

from канон import ОшибкаВхода, кодировать, прочитать, требовать
from объекты import ОбъектыГит, подготовить_дерево
from диалог import экспортировать
from вход import РеестрВходов, проверить_вход, допустить_исполнение


def внешний_файл(имя, корень):
    файл = Path(имя).absolute()
    требовать(файл == файл.resolve() and файл.is_file(), 'вход должен быть обычным файлом без symlink')
    требовать(not файл.is_relative_to(корень.resolve()), 'запись и конверт должны находиться вне принимаемого дерева')
    return файл.read_bytes()


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--корень-репозитория', required=True, type=Path)
    команды = разбор.add_subparsers(dest='команда', required=True)
    подготовка = команды.add_parser('подготовить-дерево')
    подготовка.add_argument('--ожидаемый-коммит', required=True)
    подготовка.add_argument('--ожидаемая-ветка', required=True)
    подготовка.add_argument('--разрешить-запись-объектов', action='store_true', required=True)
    ссылка = команды.add_parser('ссылка')
    ссылка.add_argument('--дерево', required=True)
    ссылка.add_argument('--путь', required=True)
    for имя in ('проверить', 'зарегистрировать'):
        проверка = команды.add_parser(имя)
        проверка.add_argument('--вход', required=True)
        проверка.add_argument('--конверт', required=True)
        проверка.add_argument('--реестр', required=True)
        проверка.add_argument('--ожидаемый-коммит', required=True)
        проверка.add_argument('--ожидаемая-ветка', required=True)
        проверка.add_argument('--зависимости', help='Внешний JSON-объект: путь gitlink → локальный репозиторий')
    экспорт = команды.add_parser('экспортировать')
    экспорт.add_argument('--источник', required=True)
    экспорт.add_argument('--задача', required=True)
    экспорт.add_argument('--курсор')
    экспорт.add_argument('--закрепить', action='store_true')
    команды.add_parser('допустить')
    параметры = разбор.parse_args()
    try:
        корень = параметры.корень_репозитория
        объекты = ОбъектыГит(корень)
        if параметры.команда == 'допустить':
            допустить_исполнение(None)
        elif параметры.команда == 'экспортировать':
            курсор = прочитать(внешний_файл(параметры.курсор, корень)) if параметры.курсор else None
            байты, квитанция = экспортировать(внешний_файл(параметры.источник, корень), параметры.задача, квитанция=курсор, закрепить=параметры.закрепить)
            # Это локальный составной ответ; только поле экспорт пригодно для дерева.
            результат = {'экспорт': прочитать(байты), 'локальная_квитанция': квитанция}
        else:
            if параметры.команда == 'ссылка':
                результат = объекты.ссылка(объекты.оид(параметры.дерево), параметры.путь)
            else:
                коммит = объекты.оид(параметры.ожидаемый_коммит)
                ветка = параметры.ожидаемая_ветка
                if параметры.команда == 'подготовить-дерево':
                    результат = {'дерево': подготовить_дерево(корень, коммит, ветка), 'исполнение_разрешено': False}
                else:
                    байты = внешний_файл(параметры.вход, корень)
                    оболочка = внешний_файл(параметры.конверт, корень)
                    реестр = РеестрВходов(параметры.реестр, корень)
                    зависимости = прочитать(внешний_файл(параметры.зависимости, корень)) if параметры.зависимости else {}
                    требовать(type(зависимости) is dict and all(type(ключ) is str and type(значение) is str for ключ, значение in зависимости.items()), 'неверная локальная карта зависимостей')
                    результат = проверить_вход(корень, байты, оболочка, ожидаемый_коммит=коммит, ожидаемая_ветка=ветка,
                                               реестр=реестр, локальные_зависимости=зависимости)
                    if параметры.команда == 'зарегистрировать':
                        реестр.зарегистрировать(байты)
        sys.stdout.buffer.write(кодировать(результат))
        return 0
    except (ОшибкаВхода, OSError) as ошибка:
        print('Отказ: ' + str(ошибка), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(выполнить())

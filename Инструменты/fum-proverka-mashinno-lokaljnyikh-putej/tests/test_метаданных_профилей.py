ПУТЬ = "Журнал/2026-10-15_17-15-40_MSK_пример-профиля/материалы/профили/профиль.json"


def пример():
    return {"схема": "fum.профиль-цепочки-подготовки.1", "режим": "чтение",
        "граница": "Синтетический профиль; ускорение рабочего цикла не заявляется.",
        "кэш_ОС_очищен": False, "среда": {"python": "3.14", "платформа": "пример"},
        "состав_sha256": {"пример.py": "a" * 64},
        "запуски": [{"первичное_чтение_нс": 1, "сверки_нс": [1, 2, 3],
            "диагностика": [{"файл": chr(126), "имя": "встроенная_" + str(номер),
                "вызовов": 1, "собственное_нс": 1} for номер in range(7)]}
            for _ in range(3)]}


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()


def заявка(сырые, путь=ПУТЬ):
    позиции = метаданные.позиции_профиля(сырые.decode())
    return {"путь": путь, "хэш_исходных_байтов": метаданные.хэш(сырые), "позиции": [
        {"строка": координаты[0], "контекст": {"вид": "встроенная-функция-cProfile",
            "поле": "файл", "запуск": запуск, "индекс": индекс}}
        for (запуск, индекс), координаты in позиции.items()]}


def классифицировать(сырые, вход=None):
    вход = вход or заявка(сырые)
    данные = {вход["путь"]: сырые}
    декларации = метаданные.вывести_декларации([вход], данные)
    политика = сканер.parse_policy({"schema": метаданные.СХЕМА_ПОЛИТИКИ,
        "exceptions": [], "метаданные": метаданные.сериализовать_декларации(декларации)})
    позиции = сканер.позиции_метаданных(политика, данные)
    return сканер.scan_text(вход["путь"], сырые.decode(),
        допущенные_метаданные=позиции[вход["путь"]])


class ГраницаПрофиля(unittest.TestCase):
    def test_21_точная_позиция_и_неизменный_предел_16(сам):
        сырые = байты(пример())
        прежние = сканер.scan_text(ПУТЬ, сырые.decode())
        сам.assertEqual(sum(к.category.startswith("error.") for к in прежние), 21)
        новые = классифицировать(сырые)
        сам.assertEqual(len(новые), 21)
        сам.assertTrue(all(к.category.startswith("allow.") for к in новые))
        сам.assertEqual(сканер.MAX_EXCEPTION_COUNT, 16)
        исключение = {"id": "profile-count", "path": ПУТЬ, "kind": "home-expansion",
            "line_sha256": "sha256:" + hashlib.sha256(b"line").hexdigest(), "count": 17,
            "category": "allow.nonpath-syntax", "reason": "Проверка сохранения прежнего предела обычных исключений."}
        with сам.assertRaisesRegex(сканер.PolicyError, "unsafe count"):
            сканер.parse_policy({"schema": сканер.POLICY_SCHEMA, "exceptions": [исключение]})

    def test_пропущенная_позиция_оставляет_ровно_один_отказ(сам):
        сырые = байты(пример()); вход = заявка(сырые)
        вход["позиции"].pop()
        находки = классифицировать(сырые, вход)
        сам.assertEqual(sum(к.category.startswith("error.") for к in находки), 1)
        сам.assertEqual(sum(к.category.startswith("allow.") for к in находки), 20)

    def test_соседние_данные_не_получают_допуск(сам):
        значение = пример(); значение["граница"] = chr(47) + "root/private"
        находки = классифицировать(байты(значение))
        сам.assertEqual(sum(к.category.startswith("allow.") for к in находки), 21)
        сам.assertEqual(sum(к.category.startswith("error.") for к in находки), 1)

    def test_неверные_индексы_поле_и_вид_отказывают(сам):
        сырые = байты(пример()); исходная = заявка(сырые)
        for поле, значение in [("запуск", True), ("запуск", -1), ("запуск", 3),
                ("индекс", True), ("индекс", -1), ("индекс", 7),
                ("поле", "имя"), ("вид", "похожий-профиль")]:
            вход = copy.deepcopy(исходная); вход["позиции"][0]["контекст"][поле] = значение
            with сам.subTest(поле=поле, значение=значение), сам.assertRaises(метаданные.ОшибкаМетаданных):
                классифицировать(сырые, вход)

    def test_другой_путь_и_повтор_позиции_отказывают(сам):
        сырые = байты(пример()); исходная = заявка(сырые)
        for путь in ["профиль.json", ПУТЬ.replace("/профили/", "/данные/"),
                ПУТЬ.replace(".json", ".md")]:
            вход = copy.deepcopy(исходная); вход["путь"] = путь
            with сам.subTest(путь=путь), сам.assertRaises(метаданные.ОшибкаМетаданных):
                классифицировать(сырые, вход)
        вход = copy.deepcopy(исходная); вход["позиции"].append(copy.deepcopy(вход["позиции"][0]))
        with сам.assertRaises(метаданные.ОшибкаМетаданных): классифицировать(сырые, вход)

    def test_закрытая_схема_типы_и_режим(сам):
        for поле, новое in [("схема", "другая"), ("режим", "запись"), ("запуски", {}),
                ("кэш_ОС_очищен", 0)]:
            значение = пример(); значение[поле] = новое
            with сам.subTest(поле=поле), сам.assertRaises(метаданные.ОшибкаМетаданных):
                метаданные.позиции_профиля(байты(значение).decode())
        значение = пример(); значение["лишнее"] = "поле"
        with сам.assertRaises(метаданные.ОшибкаМетаданных): метаданные.позиции_профиля(байты(значение).decode())

    def test_пути_вместо_маркера_не_принимаются(сам):
        значение = пример(); значение["запуски"][0]["диагностика"][0]["файл"] = chr(126) + "/private"
        сырые = байты(значение)
        находки = классифицировать(сырые)
        сам.assertEqual(sum(к.category.startswith("allow.") for к in находки), 20)
        сам.assertEqual(sum(к.category.startswith("error.") for к in находки), 1)

    def test_сырые_байты_строка_и_маркер_закреплены(сам):
        сырые = байты(пример()); вход = заявка(сырые)
        декл = метаданные.сериализовать_декларации(метаданные.вывести_декларации([вход], {ПУТЬ: сырые}))
        for поле in ["хэш_исходных_байтов", "хэш_строки", "хэш_идентификатора", "строка"]:
            испорчено = copy.deepcopy(декл)
            цель = испорчено[0] if поле == "хэш_исходных_байтов" else испорчено[0]["позиции"][0]
            цель[поле] = 1 if поле == "строка" else "sha256:" + "0" * 64
            with сам.subTest(поле=поле), сам.assertRaises(метаданные.ОшибкаМетаданных):
                метаданные.проверить_декларации(метаданные.разобрать_декларации(испорчено), {ПУТЬ: сырые})

    def test_неоднозначное_и_неканоническое_представление_отказывает(сам):
        текст = байты(пример()).decode()
        варианты = [текст.replace("\n", "\r\n"), текст.replace('"схема":', '"схема": null, "схема":', 1),
            текст.replace('"первичное_чтение_нс": 1', '"первичное_чтение_нс": NaN', 1),
            json.dumps(пример(), ensure_ascii=False), текст.replace(chr(126), "\\u007e", 1)]
        for вариант in варианты:
            with сам.subTest(sha=hashlib.sha256(вариант.encode()).hexdigest()), сам.assertRaises(метаданные.ОшибкаМетаданных):
                метаданные.позиции_профиля(вариант)

    def test_штатный_обновитель_полный_сканер_и_точный_повтор(сам):
        сырые = байты(пример())
        with tempfile.TemporaryDirectory(prefix="fum-profile-policy-") as каталог:
            корень = Path(каталог).resolve()
            subprocess.run(["git", "init", "--quiet", str(корень)], check=True)
            профиль = корень / ПУТЬ; профиль.parent.mkdir(parents=True)
            профиль.write_bytes(сырые)
            (корень / Path(ПУТЬ).parents[2] / "запрос.md").write_text("Фикстура.\n", encoding="utf-8")
            политика = корень / "policy.json"
            политика.write_bytes(байты({"schema": сканер.POLICY_SCHEMA, "exceptions": []}))
            сам.assertEqual(обновление.update_policy(корень, политика, [], метаданные=[заявка(сырые)]), 1)
            до = (политика.read_bytes(), политика.stat().st_ino, политика.stat().st_mtime_ns)
            сам.assertEqual(обновление.update_policy(корень, политика, [], метаданные=[заявка(сырые)]), 0)
            сам.assertEqual(до, (политика.read_bytes(), политика.stat().st_ino, политика.stat().st_mtime_ns))
            сам.assertEqual(сканер.scan_repository(корень, политика).exit_code, 0)
            сам.assertEqual(профиль.read_bytes(), сырые)


if __name__ == "__main__":
    unittest.main()

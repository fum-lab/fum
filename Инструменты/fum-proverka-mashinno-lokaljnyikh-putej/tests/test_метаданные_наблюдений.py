def канонические_данные(значение):
    return (json.dumps(значение, ensure_ascii=False, indent=2) + "\n").encode()


def блок_наблюдения(метка=None):
    метка = метка or chr(47) + "root/example"
    тело = "Message Type: MESSAGE\nTask name: " + метка + "\nSender: " + метка + "\nPayload:\n"
    маркер = {"длина_текста": len(тело.encode()), "идентификатор": "a" * 64,
        "источник": {"sha256": "a" * 64, "задача": "01a07d3d-d376-7ad2-aafc-67e4c25a67eb",
            "начало": 7, "конец": 9}, "предыдущий": "b" * 64, "роль": "наблюдение", "цепочка": "c" * 64}
    return ("<!-- FUM-ЖУРНАЛ:ЗАПИСЬ " + json.dumps(маркер, ensure_ascii=False) + " -->\n```text\n"
        + тело + "```\n<!-- FUM-ЖУРНАЛ:КОНЕЦ-ЗАПИСИ -->\n").encode()


def заявка(сырые, путь=ОТЧЁТ):
    return {"путь": путь, 'хэш_исходных_байтов': метаданные.хэш(сырые), "позиции": [
        {"строка": 4, "контекст": {"вид": "заголовок-наблюдения", "поле": "Task name"}},
        {"строка": 5, "контекст": {"вид": "заголовок-наблюдения", "поле": "Sender"}},
    ]}



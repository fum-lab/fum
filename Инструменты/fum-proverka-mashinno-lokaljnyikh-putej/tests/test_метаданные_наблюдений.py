class ПроверкиОбновленияМетаданных(unittest.TestCase):
    def подготовить(сам, корень):
        subprocess.run(["git", "init", "-q", str(корень)], check=True)
        сырые = блок_наблюдения()
        цель = корень / ОТЧЁТ
        цель.parent.mkdir(parents=True)
        цель.write_bytes(сырые)
        политика = корень / "policy.json"
        политика.write_bytes(канонические_данные({"schema": сканер.POLICY_SCHEMA, "exceptions": []}))
        return политика, сырые

    def test_типизированное_обновление_и_повтор_без_перезаписи(сам):
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный)
            политика, сырые = сам.подготовить(корень)
            вход = [заявка(сырые)]
            сам.assertEqual(обновление.update_policy(корень, политика, [], метаданные=вход), 1)
            значение = json.loads(политика.read_bytes())
            сам.assertEqual(значение["schema"], метаданные.СХЕМА_ПОЛИТИКИ)
            сам.assertEqual(len(значение["метаданные"][0]["позиции"]), 2)
            сам.assertNotIn(chr(47) + "root", политика.read_text())
            до = политика.stat()
            сам.assertEqual(обновление.update_policy(корень, политика, [], метаданные=вход), 0)
            сам.assertEqual((политика.stat().st_ino, политика.stat().st_mtime_ns), (до.st_ino, до.st_mtime_ns))

    def test_дрейф_источника_перед_заменой_не_пишет_политику(сам):
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный)
            политика, сырые = сам.подготовить(корень)
            исходная = политика.read_bytes()
            замена = обновление.os.replace
            исходная_синхронизация = обновление.os.fsync
            def изменить_источник(дескриптор):
                исходная_синхронизация(дескриптор)
                (корень / ОТЧЁТ).write_bytes(сырые + b"changed\n")
            with mock.patch.object(обновление.os, "fsync", side_effect=изменить_источник), \
                    mock.patch.object(обновление.os, "replace", wraps=замена) as эффект:
                with сам.assertRaises(обновление.UpdateError):
                    обновление.update_policy(корень, политика, [], метаданные=[заявка(сырые)])
                эффект.assert_not_called()
            сам.assertEqual(политика.read_bytes(), исходная)

    def test_манифест_третьей_версии_проверяет_явные_координаты(сам):
        with tempfile.TemporaryDirectory() as временный:
            путь = Path(временный) / "manifest.json"
            сырые = блок_наблюдения()
            путь.write_bytes(канонические_данные({"schema": "fum.machine-local-path-policy-update.v3",
                "declarations": [], "retirements": [], "метаданные": [заявка(сырые)]}))
            план = обновление.load_update_plan(путь)
            сам.assertEqual(len(план.метаданные), 1)

    def test_обычное_обновление_сохраняет_метаданные_а_коллизия_закрыта(сам):
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный)
            политика, сырые = сам.подготовить(корень)
            обновление.update_policy(корень, политика, [], метаданные=[заявка(сырые)])
            сохранённые = json.loads(политика.read_bytes())["метаданные"]
            (корень / "пример.txt").write_text(chr(47) + "root/example\n")
            декларация = {"id": "fixture-exact", "path": "пример.txt", "line": 1,
                "category": "allow.test-fixture", "reason": "Конечный синтетический пример для старого контракта."}
            сам.assertEqual(обновление.update_policy(корень, политика, [декларация]), 1)
            сам.assertEqual(json.loads(политика.read_bytes())["метаданные"], сохранённые)
            до = политика.read_bytes()
            новые = блок_наблюдения(chr(47) + "root/new")
            (корень / ОТЧЁТ).write_bytes(новые)
            with сам.assertRaisesRegex(обновление.UpdateError, "коллизия"):
                обновление.update_policy(корень, политика, [], метаданные=[заявка(новые)])
            сам.assertEqual(политика.read_bytes(), до)


class ПроверкиОркестрацииМетаданных(unittest.TestCase):
    def setUp(сам):
        каталог = КАТАЛОГ.parents[1] / "fum-svyaznostj-rabochej-sessii/scripts"
        sys.path.insert(0, str(каталог))
        import публикационный_допуск_дочернего_состава as адаптер
        import подготовка_дочернего_поручения as композиция
        сам.адаптер = адаптер
        сам.композиция = композиция

    def полная_политика(сам, сырые):
        первый = заявка(сырые)
        второй = заявка(сырые, ОТЧЁТ.replace("пример-наблюдения", "вне-состава"))
        выведено = метаданные.вывести_декларации([первый, второй], {ОТЧЁТ: сырые, второй["путь"]: сырые})
        return {"schema": метаданные.СХЕМА_ПОЛИТИКИ, "exceptions": [],
            "метаданные": метаданные.сериализовать_декларации(выведено)}

    def test_индекс_исполняет_проверенный_новый_модуль_и_сохраняет_позиции(сам):
        сырые = блок_наблюдения(); политика = сам.полная_политика(сырые)
        код = {имя: ((сам.адаптер.КОРЕНЬ_КОДА / путь).read_bytes(), 0o644)
            for имя, путь in сам.адаптер.ИСХОДНИКИ_СКАНЕРА}
        сам.assertIn("метаданные_наблюдений", код)
        with сам.адаптер.сканер(код) as модуль:
            итог = сам.адаптер.сканировать(модуль, {ОТЧЁТ: сырые}, [ОТЧЁТ], политика)
            сам.assertEqual(итог["код"], 0)
            сам.assertEqual(len(итог["находки"]), 2)
            with сам.assertRaises(модуль.PolicyError):
                сам.адаптер.сканировать(модуль, {ОТЧЁТ: сырые + b"changed"}, [ОТЧЁТ], политика)

    def test_будущая_композиция_также_проверяет_те_же_байты(сам):
        сырые = блок_наблюдения(); политика = сам.полная_политика(сырые)
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный)
            файл = корень / "Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/policy.json"
            файл.parent.mkdir(parents=True); файл.write_bytes(канонические_данные(политика))
            итог = сам.композиция.публикация(корень, {ОТЧЁТ: сырые})
            сам.assertEqual(итог["кандидатов"], 2)
            with сам.assertRaises(ValueError): сам.композиция.публикация(корень, {ОТЧЁТ: сырые + b"changed"})



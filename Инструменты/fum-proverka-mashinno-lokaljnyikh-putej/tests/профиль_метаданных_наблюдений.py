"""Сравнить стоимость прежнего отказа и нового точного допуска 38 меток."""
import argparse
import hashlib
import json
from pathlib import Path
import statistics
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_метаданные_наблюдений as примеры


def выполнить(повторов):
    if type(повторов) is not int or повторов < 3:
        raise ValueError("нужно не менее трёх повторов")
    м = примеры.метаданные
    с = примеры.сканер
    исходники = [Path(__file__), Path(примеры.__file__), Path(м.__file__), Path(с.__file__),
        Path(примеры.обновление.__file__), Path(sys.modules["path_forms"].__file__),
        Path(sys.modules["request_folder_layout"].__file__)]
    def снимок():
        return {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in исходники}
    до = снимок()
    отчёт = b"".join(примеры.блок_наблюдения(chr(47) + "root/a" + str(индекс)) for индекс in range(18))
    заявка = примеры.заявка(отчёт)
    заявка["позиции"] = [{"строка": 8 * индекс + номер, "контекст": {"вид": "заголовок-наблюдения", "поле": поле}}
        for индекс in range(18) for номер, поле in [(4, "Task name"), (5, "Sender")]]
    сверка = примеры.канонические_данные(примеры.пример_сверки())
    второй = примеры.заявка_сверки(сверка)
    данные = {примеры.ОТЧЁТ: отчёт, второй["путь"]: сверка}
    выведено = м.вывести_декларации([заявка, второй], данные)
    значение = {"schema": м.СХЕМА_ПОЛИТИКИ, "exceptions": [], "метаданные": м.сериализовать_декларации(выведено)}
    времена = {"прежний-отказ": [], "типизированный-допуск": []}
    исходы = {}
    for _ in range(повторов):
        for имя in времена:
            начало = time.monotonic_ns()
            политика = с.parse_policy(значение if имя == "типизированный-допуск" else
                {"schema": с.POLICY_SCHEMA, "exceptions": []})
            позиции = с.позиции_метаданных(политика, данные)
            кандидаты = [к for п, б in данные.items() for к in с.scan_text(п, б.decode(),
                допущенные_метаданные=позиции.get(п, frozenset()))]
            времена[имя].append(time.monotonic_ns() - начало)
            исходы[имя] = {"кандидатов": len(кандидаты),
                "ошибок": sum(к.category.startswith("error.") for к in кандидаты)}
    if до != снимок() or исходы != {"прежний-отказ": {"кандидатов": 38, "ошибок": 38},
            "типизированный-допуск": {"кандидатов": 38, "ошибок": 0}}:
        raise ValueError("дрейф кода либо неверный исход профиля")
    return {"схема": "fum.профиль-метаданных-наблюдений.1", "повторов": повторов,
        'хэши_исходников': до, 'хэши_входов': {п: м.хэш(б) for п, б in данные.items()},
        "исходы": исходы, "медианы_нс": {имя: statistics.median(ряд) for имя, ряд in времена.items()},
        "интервалы_нс": времена,
        "граница": "Одинаковые синтетические байты; прежний отказ не эквивалентен новому допуску. "
            "Интервалы включают parse, SHA, контекст и классификацию; подготовка исключена. "
            "Профиль не доказывает ускорение всего приёмочного контура."}


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--повторов", type=int, default=25)
    параметры = разбор.parse_args()
    print(json.dumps(выполнить(параметры.повторов), ensure_ascii=False, sort_keys=True, indent=2))

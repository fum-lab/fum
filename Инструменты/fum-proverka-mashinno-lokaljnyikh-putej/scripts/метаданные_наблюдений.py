"""Конечный допуск меток runtime в двух закрытых форматах наблюдений.

Декларация связывает точные байты файла и позиции. Остальное содержимое
проверяет обычный сканер; допуск не распространяется даже на соседний путь.
"""
from dataclasses import dataclass
import hashlib
import json
from pathlib import PurePosixPath
import re
import uuid
import unicodedata

from path_forms import detect_path_forms
from request_folder_layout import session_stem_for_request_path


СХЕМА_ПОЛИТИКИ = "fum.machine-local-path-policy.v3"
СХЕМА_СВЕРКИ = "fum.независимая-сверка-переименования.1"
ПОЛЯ_ЗАПИСИ = frozenset({"путь", 'хэш_исходных_байтов', "позиции"})
ПОЛЯ_ПОЗИЦИИ = frozenset({"строка", 'хэш_строки', 'хэш_идентификатора', "контекст"})
ШАБЛОН_ХЭША = re.compile(r"sha256:[0-9a-f]{64}\Z")
ШАБЛОН_СЫРОГО_ХЭША = re.compile(r"[0-9a-f]{64}\Z")
ШАБЛОН_КОММИТА = re.compile(r"[0-9a-f]{40}\Z")
ПОЛЯ_МАРКЕРА = frozenset({"длина_текста", "идентификатор", "источник", "предыдущий", "роль", "цепочка"})
ПОЛЯ_ИСТОЧНИКА = frozenset({"sha256", "задача", "начало", "конец"})
ПОЛЯ_СВЕРКИ = frozenset({"схема", "исходный-коммит", "помощники", "режим-помощников",
    "предметный-вывод", "проверка-вычисления-путей", "gitmodules-sha256", "gitlink", "файлы",
    "пустой-каркас-до-очистки", "очистка-корнем", "прежний-каталог-отсутствует", "граница"})
ПОЛЯ_ФАЙЛА = frozenset({"из", "в", "sha256-H", "sha256-после", "режим", "предметные-байты-равны"})


class ОшибкаМетаданных(ValueError):
    """Декларация или её точный выбранный источник недостоверны."""


def требовать(условие, сообщение):
    if not условие:
        raise ОшибкаМетаданных(сообщение)


def хэш(сырые):
    return "sha256:" + hashlib.sha256(сырые).hexdigest()


def поля(значение, ожидаемые):
    требовать(type(значение) is dict and set(значение) == set(ожидаемые), "неверные поля метаданных")


def объект_без_повторов(пары):
    результат = {}
    for имя, значение in пары:
        требовать(имя not in результат, "повторяющийся ключ JSON")
        результат[имя] = значение
    return результат


def разобрать_данные(сырые):
    def неизвестная_константа(имя):
        raise ОшибкаМетаданных("неизвестная константа JSON")
    try:
        return json.loads(сырые, object_pairs_hook=объект_без_повторов, parse_constant=неизвестная_константа)
    except (ValueError, UnicodeError) as ошибка:
        raise ОшибкаМетаданных("повреждённый или неоднозначный JSON") from ошибка


@dataclass(frozen=True)
class ПозицияМетаданных:
    строка: int
    хэш_строки: str
    хэш_идентификатора: str
    вид: str
    поле: str
    индекс: int | None = None


@dataclass(frozen=True)
class ДекларацияМетаданных:
    путь: str
    хэш_исходных_байтов: str
    позиции: tuple[ПозицияМетаданных, ...]


def разобрать_декларации(значение):
    требовать(type(значение) is list, "метаданные должны быть массивом")
    результат = []
    пути = set()
    for запись in значение:
        поля(запись, ПОЛЯ_ЗАПИСИ)
        путь = запись["путь"]
        требовать(type(путь) is str and путь and unicodedata.normalize("NFC", путь) == путь
            and "\\" not in путь and not any(с in путь for с in "\0\r\n")
            and not any(с in путь for с in "*?[]"), "неверный точный путь метаданных")
        части = PurePosixPath(путь).parts
        требовать(PurePosixPath(путь).as_posix() == путь and ".." not in части
            and len(части) >= 3 and части[0] == "Журнал" and путь not in пути,
            "метаданные вне точного канонического Журнала")
        требовать(session_stem_for_request_path(f"Журнал/{части[1]}/запрос.md") == части[1],
            "неканоническая папка метаданных")
        пути.add(путь)
        требовать(type(запись['хэш_исходных_байтов']) is str
            and ШАБЛОН_ХЭША.fullmatch(запись['хэш_исходных_байтов']), "неверный RAW SHA метаданных")
        требовать(type(запись["позиции"]) is list and запись["позиции"], "пустая декларация метаданных")
        позиции = []
        ключи = set()
        for позиция in запись["позиции"]:
            поля(позиция, ПОЛЯ_ПОЗИЦИИ)
            требовать(type(позиция["строка"]) is int and позиция["строка"] > 0, "неверная строка метаданных")
            for имя in ('хэш_строки', 'хэш_идентификатора'):
                требовать(type(позиция[имя]) is str and ШАБЛОН_ХЭША.fullmatch(позиция[имя]),
                    "неверный SHA позиции метаданных")
            контекст = позиция["контекст"]
            требовать(type(контекст) is dict, "неверный контекст метаданных")
            вид = контекст.get("вид")
            if вид == "заголовок-наблюдения":
                поля(контекст, {"вид", "поле"})
                требовать(type(контекст["поле"]) is str and контекст["поле"] in {"Task name", "Sender"}
                    and len(части) == 3 and части[2] == "отчёт.md", "неверное поле заголовка")
                индекс = None
            elif вид == "сверка-переименования":
                поля(контекст, {"вид", "поле", "индекс"})
                индекс = контекст["индекс"]
                требовать(контекст["поле"] == "помощники" and type(индекс) is int and индекс in {0, 1}
                    and len(части) == 4 and части[2:] == ("материалы", "независимая-сверка.json"),
                    "неверное поле сверки")
            else:
                raise ОшибкаМетаданных("неизвестный вид метаданных")
            ключ = (позиция["строка"], контекст["поле"], индекс)
            требовать(ключ not in ключи, "повторяющаяся позиция метаданных")
            ключи.add(ключ)
            позиции.append(ПозицияМетаданных(позиция["строка"], позиция['хэш_строки'],
                позиция['хэш_идентификатора'], вид, контекст["поле"], индекс))
        результат.append(ДекларацияМетаданных(путь, запись['хэш_исходных_байтов'], tuple(позиции)))
    return tuple(результат)


def сериализовать_декларации(декларации):
    результат = []
    for запись in декларации:
        позиции = []
        for позиция in запись.позиции:
            контекст = {"вид": позиция.вид, "поле": позиция.поле}
            if позиция.индекс is not None:
                контекст["индекс"] = позиция.индекс
            позиции.append({"строка": позиция.строка, 'хэш_строки': позиция.хэш_строки,
                'хэш_идентификатора': позиция.хэш_идентификатора, "контекст": контекст})
        результат.append({"путь": запись.путь, 'хэш_исходных_байтов': запись.хэш_исходных_байтов, "позиции": позиции})
    return результат


def разобрать_заявки(заявки):
    """В manifest нужны только явные координаты и RAW SHA, без ручных fingerprints."""
    требовать(type(заявки) is list, "заявки метаданных должны быть массивом")
    заполненные = []
    for заявка in заявки:
        поля(заявка, ПОЛЯ_ЗАПИСИ)
        требовать(type(заявка["позиции"]) is list, "неверные позиции заявки")
        позиции = []
        for позиция in заявка["позиции"]:
            поля(позиция, {"строка", "контекст"})
            позиции.append({**позиция, 'хэш_строки': "sha256:" + "0" * 64,
                'хэш_идентификатора': "sha256:" + "0" * 64})
        заполненные.append({**заявка, "позиции": позиции})
    return разобрать_декларации(заполненные)


def вывести_декларации(заявки, данные):
    результат = []
    for заявка in разобрать_заявки(заявки):
        требовать(заявка.путь in данные and type(данные[заявка.путь]) is bytes, "нет RAW источника заявки")
        сырые = данные[заявка.путь]
        требовать(хэш(сырые) == заявка.хэш_исходных_байтов and b"\0" not in сырые, "дрейф RAW источника заявки")
        try:
            текст = сырые.decode("utf-8")
        except UnicodeError as ошибка:
            raise ОшибкаМетаданных("не UTF-8 источник заявки") from ошибка
        строки = текст.splitlines(keepends=True)
        позиции = []
        сверка = None
        for позиция in заявка.позиции:
            требовать(позиция.строка <= len(строки), "нет строки заявки")
            if позиция.вид == "заголовок-наблюдения":
                номер, _, _, метка = позиция_заголовка(строки, позиция)
            else:
                if сверка is None:
                    сверка = позиции_сверки(текст)
                номер, _, _, метка = сверка[позиция.индекс]
            требовать(номер == позиция.строка, "координаты заявки не соответствуют контексту")
            строка = строки[номер - 1].removesuffix("\n")
            позиции.append(ПозицияМетаданных(номер, хэш(строка.encode("utf-8")),
                хэш(метка.encode("utf-8")), позиция.вид, позиция.поле, позиция.индекс))
        результат.append(ДекларацияМетаданных(заявка.путь, заявка.хэш_исходных_байтов, tuple(позиции)))
    проверить_декларации(результат, данные)
    return tuple(результат)


def проверить_метку(значение):
    корень = chr(47) + "root"
    требовать(type(значение) is str and re.fullmatch(re.escape(корень) + r"(?:/[a-z0-9_]+)*", значение),
        "значение не является меткой runtime")
    формы = detect_path_forms(значение)
    требовать(len(формы) == 1 and формы[0].kind == "posix-user-home"
        and формы[0].start == 0 and формы[0].end == len(значение), "неоднозначная метка runtime")


def проверить_маркер(строка, тело):
    совпадение = re.fullmatch(r"<!-- FUM-ЖУРНАЛ:ЗАПИСЬ (.+) -->", строка)
    требовать(совпадение is not None, "нет закрытого маркера наблюдения")
    маркер = разобрать_данные(совпадение[1])
    поля(маркер, ПОЛЯ_МАРКЕРА)
    требовать(маркер["роль"] == "наблюдение" and type(маркер["длина_текста"]) is int
        and маркер["длина_текста"] == len(тело.encode("utf-8")), "неверная роль или длина наблюдения")
    for имя in ("идентификатор", "предыдущий", "цепочка"):
        требовать(type(маркер[имя]) is str and ШАБЛОН_СЫРОГО_ХЭША.fullmatch(маркер[имя]),
            "неверный хэш маркера")
    источник = маркер["источник"]
    поля(источник, ПОЛЯ_ИСТОЧНИКА)
    требовать(type(источник["sha256"]) is str and ШАБЛОН_СЫРОГО_ХЭША.fullmatch(источник["sha256"])
        and источник["sha256"] == маркер["идентификатор"], "неверная ссылка на первичное событие")
    try:
        требовать(type(источник["задача"]) is str and str(uuid.UUID(источник["задача"])) == источник["задача"],
            "неверный UUID наблюдения")
    except (ValueError, AttributeError) as ошибка:
        raise ОшибкаМетаданных("неверный UUID наблюдения") from ошибка
    требовать(type(источник["начало"]) is int and type(источник["конец"]) is int
        and 0 <= источник["начало"] < источник["конец"], "неверные координаты первичного события")


def позиция_заголовка(строки, позиция):
    смещение = 3 if позиция.поле == "Task name" else 4
    начало = позиция.строка - 1 - смещение
    требовать(начало >= 0 and начало + 8 <= len(строки), "неполный блок наблюдения")
    блок = строки[начало:начало + 8]
    требовать(all(строка.endswith("\n") and not строка.endswith("\r\n") for строка in блок),
        "неподдержанный перевод строки наблюдения")
    чистые = [строка[:-1] for строка in блок]
    требовать(чистые[1] == "```text" and чистые[2] == "Message Type: MESSAGE"
        and чистые[5] == "Payload:" and чистые[6] == "```"
        and чистые[7] == "<!-- FUM-ЖУРНАЛ:КОНЕЦ-ЗАПИСИ -->", "незамкнутый контекст наблюдения")
    проверить_маркер(чистые[0], "".join(блок[2:6]))
    for номер, поле in ((3, "Task name"), (4, "Sender")):
        префикс = поле + ": "
        требовать(чистые[номер].startswith(префикс), "неверный порядок полей наблюдения")
        проверить_метку(чистые[номер][len(префикс):])
    префикс = позиция.поле + ": "
    значение = чистые[смещение][len(префикс):]
    return позиция.строка, len(префикс), len(префикс) + len(значение), значение


def позиции_сверки(текст):
    требовать(not any(с in текст for с in "\r\v\f\x1c\x1d\x1e\x85\u2028\u2029"),
        "неподдержанный разделитель строк JSON-сверки")
    значение = разобрать_данные(текст)
    поля(значение, ПОЛЯ_СВЕРКИ)
    требовать(значение["схема"] == СХЕМА_СВЕРКИ, "неизвестная схема сверки")
    for имя in ("исходный-коммит", "gitlink"):
        требовать(type(значение[имя]) is str and ШАБЛОН_КОММИТА.fullmatch(значение[имя]), "неверный коммит сверки")
    требовать(type(значение["gitmodules-sha256"]) is str
        and ШАБЛОН_СЫРОГО_ХЭША.fullmatch(значение["gitmodules-sha256"]), "неверный SHA сверки")
    требовать(type(значение["помощники"]) is list and len(значение["помощники"]) == 2, "неверный массив помощников")
    for метка in значение["помощники"]:
        проверить_метку(метка)
    требовать(type(значение["файлы"]) is list and len(значение["файлы"]) == 12, "неверный состав сверки")
    for файл in значение["файлы"]:
        поля(файл, ПОЛЯ_ФАЙЛА)
        требовать(all(type(файл[имя]) is str for имя in ("из", "в"))
            and all(type(файл[имя]) is str and ШАБЛОН_СЫРОГО_ХЭША.fullmatch(файл[имя])
                for имя in ("sha256-H", "sha256-после"))
            and файл["режим"] == "0644" and type(файл["предметные-байты-равны"]) is bool,
            "неверный файл сверки")
    требовать(type(значение["очистка-корнем"]) is list and len(значение["очистка-корнем"]) == 8
        and all(type(путь) is str for путь in значение["очистка-корнем"])
        and type(значение["прежний-каталог-отсутствует"]) is bool, "неверный итог очистки сверки")
    for имя in ПОЛЯ_СВЕРКИ - {"схема", "исходный-коммит", "gitlink", "gitmodules-sha256", "помощники",
            "файлы", "очистка-корнем", "прежний-каталог-отсутствует"}:
        требовать(type(значение[имя]) is str, "неверное текстовое поле сверки")
    совпадения = list(re.finditer(r'"помощники"\s*:\s*\[', текст))
    требовать(len(совпадения) == 1, "неоднозначные координаты массива помощников")
    курсор = совпадения[0].end()
    результат = {}
    декодер = json.JSONDecoder()
    for индекс, метка in enumerate(значение["помощники"]):
        while курсор < len(текст) and текст[курсор].isspace():
            курсор += 1
        прочитано, конец = декодер.raw_decode(текст, курсор)
        требовать(прочитано == метка and текст[курсор:конец] == json.dumps(метка, ensure_ascii=False),
            "неподдержанное кодирование метки помощника")
        строка = текст.count("\n", 0, курсор) + 1
        начало = курсор + 1 - (текст.rfind("\n", 0, курсор) + 1)
        результат[индекс] = (строка, начало, начало + len(метка), метка)
        курсор = конец
        while курсор < len(текст) and текст[курсор].isspace():
            курсор += 1
        требовать(курсор < len(текст) and текст[курсор] == ("," if индекс == 0 else "]"),
            "неверная граница массива помощников")
        курсор += 1
    return результат


def проверить_декларации(декларации, данные):
    результат = {}
    for запись in декларации:
        требовать(запись.путь in данные and type(данные[запись.путь]) is bytes, "нет выбранного RAW источника метаданных")
        сырые = данные[запись.путь]
        требовать(хэш(сырые) == запись.хэш_исходных_байтов and b"\0" not in сырые, "дрейф RAW источника метаданных")
        try:
            текст = сырые.decode("utf-8")
        except UnicodeError as ошибка:
            raise ОшибкаМетаданных("не UTF-8 источник метаданных") from ошибка
        строки = текст.splitlines(keepends=True)
        диапазоны = set()
        сверка = None
        for позиция in запись.позиции:
            требовать(позиция.строка <= len(строки), "отсутствующая строка метаданных")
            строка = строки[позиция.строка - 1].removesuffix("\n")
            требовать(хэш(строка.encode("utf-8")) == позиция.хэш_строки, "дрейф строки метаданных")
            if позиция.вид == "заголовок-наблюдения":
                номер, начало, конец, метка = позиция_заголовка(строки, позиция)
            else:
                if сверка is None:
                    сверка = позиции_сверки(текст)
                номер, начало, конец, метка = сверка[позиция.индекс]
            требовать(номер == позиция.строка and хэш(метка.encode("utf-8")) == позиция.хэш_идентификатора,
                "дрейф координат или ID метаданных")
            требовать(строка[начало:конец] == метка, "диапазон не соответствует метке исходной строки")
            диапазон = (номер, начало, конец)
            требовать(диапазон not in диапазоны, "повторяющийся диапазон метаданных")
            диапазоны.add(диапазон)
        результат[запись.путь] = frozenset(диапазоны)
    return результат

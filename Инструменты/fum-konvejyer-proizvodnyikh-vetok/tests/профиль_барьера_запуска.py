"""Профиль первоначальных прав и закрытия одной задачи на открытой Git-фикстуре."""
import argparse
from contextlib import ExitStack
import hashlib
import json
import os
from pathlib import Path
import statistics
import time
from unittest import mock

from фикстура_барьера_запуска import один_до_записи
from test_запуска_слоёв import хранение, постановка
import права_запуска
import завершение_одного_до_записи as закрытие
import терминал_запуска


def измерить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--выход', required=True)
    аргументы = парсер.parse_args()
    фазы = []

    def серия(имя, число, действие):
        времена, результаты = [], []
        for _ in range(число):
            начало = time.perf_counter_ns()
            результаты.append(действие())
            времена.append(time.perf_counter_ns() - начало)
        assert all(р == результаты[0] for р in результаты)
        фазы.append({'стадия': имя, 'вызовов': число, 'наносекунды': времена,
                     'минимум': min(времена), 'медиана': int(statistics.median(времена)), 'максимум': max(времена)})
        return результаты[0]

    начало = time.perf_counter_ns()
    with один_до_записи() as (_, объект, пакет, план, вход, _, ребёнок):
        подготовка = time.perf_counter_ns() - начало
        дерево, задача, источник, _ = ребёнок
        база = пакет['постановка']['коммит']
        до = объект.хранилище.прочитать()
        байты_до = объект.хранилище.путь.read_bytes()
        refs = хранение.гит(дерево, 'show-ref')
        права = серия('чтение первоначальных прав', 7, lambda: права_запуска.прочитать(дерево, задача, база, источник))
        with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': задача}):
            проверка = серия('проверка ребёнка до записи', 3, lambda: права_запуска.проверить_до_записи(дерево, задача, источник))
        assert права['разрешение_записи'] is проверка['разрешение_записи'] is False
        assert хранение.гит(дерево, 'show-ref') == refs and not хранение.гит(дерево, 'status', '--porcelain')
        assert not постановка.путь_подтверждения(дерево).exists()
        assert объект.хранилище.путь.read_bytes() == байты_до
        результат = серия('предпросмотр закрытия одной задачи', 3, lambda: закрытие.предпросмотр(объект, вход))
        итог = серия('сверка под замком и запись', 1, lambda: закрытие.завершить(объект, вход, результат['sha256']))
        assert итог == результат
        после = объект.хранилище.прочитать()
        assert после['приёмы'].pop(терминал_запуска.ключ(план['запуск'])) == результат and после == до
        assert план['попытки']['сообщения'] not in после['попытки']
        байты_после = объект.хранилище.путь.read_bytes()
        цели = [(закрытие.нативные_вызовы, 'прочитать'), (закрытие.остановка_ребёнка, 'проверить'),
                (закрытие.возобновления_до_записи, 'проверить'), (закрытие, '_снимок_корня')]
        with ExitStack() as стек:
            запреты = [стек.enter_context(mock.patch.object(м, имя, side_effect=AssertionError('Повтор читает живой источник')))
                       for м, имя in цели]
            assert серия('исторический повтор без живых чтений', 7,
                         lambda: закрытие.завершить(объект, вход, результат['sha256'])) == результат
            for запрет in запреты:
                запрет.assert_not_called()
        assert объект.хранилище.путь.read_bytes() == байты_после
        размеры = {'префикс_прав': права['источник']['граница'], 'префикс_поручения': проверка['поручение']['граница'],
                   'JSONL_ребёнка': источник.stat().st_size, 'JSONL_корня': вход['источник']['граница'],
                   'реестр_до': len(байты_до), 'реестр_после': len(байты_после)}
    каталог = Path(__file__).resolve().parents[1]
    пути = set(права_запуска.КОД) | set(закрытие.КОД) | {Path(__file__).resolve(), каталог / 'tests' / 'фикстура_барьера_запуска.py'}
    вывод = {'схема': 'fum.профиль-барьера-запуска.1', 'подготовка_фикстуры_наносекунды': подготовка,
             'фазы': фазы, 'размеры_байтов': размеры,
             'граница': 'Настоящий временный Git, синтетический Native, без Desktop и сети. Совпадение кода с C подменено только фикстурой. '
                        'Читатель наблюдает первый turn_context, а не системную способность записи. Стоимость второго допуска и больших источников не измерена. '
                        'Запись терминала измерена один раз; исторические повторы запрещают четыре вида живого чтения.',
             'исходники': {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in sorted(пути)}}
    with Path(аргументы.выход).open('x', encoding='utf-8') as поток:
        json.dump(вывод, поток, ensure_ascii=False, indent=2)
        поток.write('\n')
    print(json.dumps(вывод, ensure_ascii=False))


if __name__ == '__main__':
    измерить()

"""Профиль чистого разбора; файловое чтение, Git и запуск получателя не измеряются."""
import hashlib
import json
from pathlib import Path
import statistics
import time

from test_исторической_квитанции_отказа import образец, сырые
import историческая_квитанция_отказа as отказ


def главная():
    пакет, основание, данные, защищённые = образец()
    верные = сырые(данные)
    данные['защищённые']['локальное.bin']['режим'] = float(защищённые['локальное.bin']['режим'])
    иные = сырые(данные)
    серии = {'неизвестная_квитанция': [], 'самосогласованная_подмена_типа': []}
    число = 300
    for номер in range(7):
        порядок = tuple(серии) if номер % 2 == 0 else tuple(reversed(серии))
        for имя in порядок:
            старт = time.perf_counter_ns()
            for _ in range(число):
                if имя == 'неизвестная_квитанция':
                    итог = отказ.проверить(верные, основание, пакет, защищённые)
                    if итог['исход_эффекта'] != 'unknown' or итог['повтор_эффекта_разрешён'] is not False:
                        raise RuntimeError('Изменена граница неизвестного эффекта')
                else:
                    try:
                        отказ.проверить(иные, основание, пакет, защищённые)
                    except ValueError:
                        pass
                    else:
                        raise RuntimeError('Принята подмена числового типа')
            серии[имя].append(time.perf_counter_ns() - старт)
    результат = {'схема': 'fum.профиль-исторической-квитанции.1',
        'граница': 'Только чистый разбор открытой фикстуры: неизвестный эффект и отказ подмены типа',
        'вызовов_на_серию': число, 'число_серий': 7,
        'код_sha256': отказ.КОД_ПРИ_ЗАГРУЗКЕ,
        'фикстура_sha256': hashlib.sha256(Path(__file__).with_name('test_исторической_квитанции_отказа.py').read_bytes()).hexdigest(),
        'серии': {имя: {'длительности_нс': значения,
            'медиана_на_вызов_нс': statistics.median(значения) / число}
            for имя, значения in серии.items()},
        'получатель_запускался': False, 'git_измерен': False,
        'база_для_сравнения': None, 'оптимизация': 'Границу измерения ограничили чистым разбором без Git и полного smoke-check'}
    print(json.dumps(результат, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False))


if __name__ == '__main__':
    главная()

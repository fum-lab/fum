"""Время читающего FS/Git-пути; построение открытой фикстуры вне измерения."""
from pathlib import Path
import statistics
import tempfile
import time
from unittest import mock

from фикстура_исторического_отказа import ФикстураИсторическогоОтказа, хранение
import конверт_приёма as конверт
import эпизод_приёма as эпизод
import прочитать_исторический_отказ as читатель


def измерить():
    серии, отказы = [], []
    with tempfile.TemporaryDirectory(prefix='fum-профиль-чтения-') as временное:
        ф = ФикстураИсторическогоОтказа(временное)
        with mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', ф.приватное), \
                mock.patch.object(эпизод, 'КОРЕНЬ_СОСТОЯНИЯ', ф.приватное / 'эпизоды'):
            def пройти():
                профиль = {}
                итог = читатель.прочитать(ф.описание_чтения, ф.текст, ф.нативный, профиль=профиль)
                assert итог['повтор_эффекта_разрешён'] is False
                return профиль
            холодный = пройти()
            for _ in range(7):
                серии.append(пройти())
                поздний = ф.намерение.with_suffix('.журнал.json')
                ф.записать_приватно(поздний, {'фикстура': 'Поздний результат'})
                начало = time.monotonic_ns()
                try:
                    with mock.patch.object(читатель, '_git', side_effect=AssertionError('Дорогой Git не нужен')):
                        try: читатель.прочитать(ф.описание_чтения, ф.текст, ф.нативный)
                        except ValueError: pass
                        else: raise AssertionError('Нет раннего отказа')
                    отказы.append(time.monotonic_ns() - начало)
                finally: поздний.unlink()
    return {'схема': 'fum.профиль-файлового-чтения-отказа.1',
        'граница': 'Открытая локальная FS/Git-фикстура; без native-допуска .9, LLM и повторной доставки',
        'единица': 'наносекунды', 'первый_вызов': холодный, 'серии': серии,
        'медианы': {к: statistics.median(с[к] for с in серии) for к in серии[0]},
        'ранний_отказ_без_Git': отказы, 'медиана_раннего_отказа': statistics.median(отказы),
        'оптимизация': 'Поздний результат обнаруживается до Git; фикстура строится один раз вне измерения',
        'парный_базовый_замер': None}


if __name__ == '__main__': print(хранение.байты(измерить()).decode(), end='')

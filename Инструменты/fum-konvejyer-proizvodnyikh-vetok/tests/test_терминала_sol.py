"""Конечные режимы Sol/Ultra сохраняют назначенные деревья и всю историю."""
import unittest

from фикстура_новых_веток import новое_поколение
from фикстура_остановленного_поколения import подготовить_остановку
from test_завершения_новых_веток import снимки
from test_запуска_слоёв import ребёнок, хранение
from test_профиля_sol import выбрать_sol
import завершение_сохранённых_писателей
import завершение_смешанного_запуска
import терминал_запуска


class ПроверкаТерминалаSol(unittest.TestCase):
    def завершить(self, объект, запуск, вход, модуль, дети):
        деревья = снимки(дети)
        до = объект.хранилище.прочитать()
        итог = модуль.предпросмотр(объект, вход)
        self.assertEqual(до, объект.хранилище.прочитать())
        self.assertEqual(итог, модуль.завершить(объект, вход, итог["sha256"]))
        после = объект.хранилище.прочитать()
        del после["приёмы"][терминал_запуска.ключ(вход["запуск"])]
        self.assertEqual(до, после)
        байты = объект.хранилище.путь.read_bytes()
        self.assertEqual(итог, модуль.завершить(объект, вход, итог["sha256"]))
        self.assertEqual(байты, объект.хранилище.путь.read_bytes())
        self.assertEqual(деревья, снимки(дети))
        for слой in вход["слои"]:
            with self.assertRaises(ValueError):
                объект.допустить(запуск, слой)

    def test_два_назначенных_писателя_с_разными_пакетами(self):
        with новое_поколение() as (корень, объект, _, запуск, описание, _, прежние):
            выбрать_sol(запуск)
            план = объект.предпросмотр(запуск)
            объект.подготовить(запуск, план["sha256"])
            дети = {}
            for номер, слой in enumerate(описание["слои"], 85):
                имя = слой["слой"]
                допуск = объект.допустить(запуск, имя)
                дети[имя] = ребёнок(корень, запуск, слой, допуск, номер,
                                    экранировать=True, модель="gpt-6-sol", усилие="ultra")
                объект.наблюдать(план["запуск"], имя, *дети[имя])
            назначение = хранение.разобрать((корень / запуск["назначение"]).read_bytes())
            вход, _ = подготовить_остановку(корень, объект, запуск, план, назначение, дети)
            все = {**{"старый-" + к: в for к, в in прежние.items()}, **дети}
            self.завершить(объект, запуск, вход, завершение_сохранённых_писателей, все)

    def test_сохранённый_писатель_и_невызванный_второй(self):
        with новое_поколение() as (корень, объект, _, запуск, описание, _, прежние):
            выбрать_sol(запуск)
            план = объект.предпросмотр(запуск)
            объект.подготовить(запуск, план["sha256"])
            допуск = объект.допустить(запуск, "события")
            дитя = ребёнок(корень, запуск, описание["слои"][0], допуск, 87,
                           экранировать=True, модель="gpt-6-sol", усилие="ultra")
            объект.наблюдать(план["запуск"], "события", *дитя)
            второй = объект.допустить(запуск, "сообщения")
            назначение = хранение.разобрать((корень / запуск["назначение"]).read_bytes())
            вход, _ = подготовить_остановку(корень, объект, запуск, план, назначение, {"события": дитя})
            вход.update(схема="fum.завершение-неудачного-запуска.4")
            вход["слои"]["сообщения"] = {"вид": "не-вызван", "попытка": второй["попытка"]}
            self.завершить(объект, запуск, вход, завершение_смешанного_запуска, {**прежние, "новый": дитя})


if __name__ == "__main__":
    unittest.main()

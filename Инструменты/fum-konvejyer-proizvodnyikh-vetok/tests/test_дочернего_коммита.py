"""Конечный коммит дочернего слоя сохраняет происхождение и прежние допуски."""
import contextlib
import copy
import importlib
import io
import json
from pathlib import Path
import sys
import unittest
from unittest import mock

from фикстура_дочернего_коммита import фикстура, коммит, НОМЕР
from test_запуска_слоёв import хранение, ЗАДАЧА


class ПроверкаДочернегоКоммита(unittest.TestCase):
    def test_готовность_сохраняет_привязку_и_возраст_после_отзыва(self):
        with фикстура() as (_, _, параметры):
            готовность = коммит.готовность
            снимок = готовность.снимок(параметры, [{'экземпляр': 'a' * 64}], [НОМЕР], {'содержимое': 'sha256:' + 'b' * 64})
            записи = [[НОМЕР, 'c' * 64]]
            with mock.patch.object(готовность.time, 'time_ns', return_value=1_000_000_000):
                первый = готовность.объявить(параметры, снимок, записи, 600)
            путь = Path(первый['путь']); до = путь.read_bytes()
            сохранённое = json.loads(до)
            self.assertEqual('fum.готовность-дочерней-передачи.1', сохранённое['схема'])
            self.assertEqual({'исполнитель': параметры['исполнитель'], 'назначение_sha256': параметры['назначение_sha256']},
                             сохранённое['привязка'])
            другой = {**параметры, 'назначение_sha256': 'f' * 64}
            self.assertEqual(путь, готовность.путь_этапа(другой))
            for вызов in (lambda: готовность.проверить_доступность(другой),
                          lambda: готовность.объявить(другой, снимок, записи, 600),
                          lambda: готовность.отозвать(другой, 0, 'Подмена'),
                          lambda: готовность.сверить(другой, снимок, записи)):
                with self.assertRaisesRegex(ValueError, 'привязк'):
                    вызов()
                self.assertEqual(до, путь.read_bytes())
            with mock.patch.object(готовность.time, 'time_ns', return_value=3_000_000_000):
                готовность.отозвать(параметры, 0, 'Повторить после проверки')
            with mock.patch.object(готовность.time, 'time_ns', return_value=5_000_000_000):
                второй = готовность.объявить(параметры, снимок, записи, 600)
            self.assertEqual(первый['готов_в_наносекундах_эпохи'], второй['готов_в_наносекундах_эпохи'])
            self.assertEqual(сохранённое['привязка'], json.loads(путь.read_bytes())['привязка'])

    def test_привязка_не_меняется_при_содержательной_записи_и_staging(self):
        with фикстура() as (корень, источник, параметры):
            читатель = importlib.import_module('дочернее_назначение')
            до = читатель.прочитать(корень, параметры['исполнитель'], источник)
            (корень / 'Память/события/данные.txt').write_text('изменено\n')
            хранение.гит(корень, 'add', '.')
            после = читатель.прочитать(корень, параметры['исполнитель'], источник)
            self.assertNotEqual(до['sha256'], после['sha256'])
            self.assertEqual(читатель.привязка(до), читатель.привязка(после))
            другое = copy.deepcopy(после); другое['назначение']['слой'] = 'другой'
            self.assertNotEqual(читатель.привязка(до), читатель.привязка(другое))

    def test_подготовка_отделяет_исполнителя_от_корневого_трейлера(self):
        with фикстура() as (корень, _, параметры):
            коммит.подготовить(параметры)
            подготовка = json.loads(Path(параметры['подготовка']).read_bytes())
            история = json.loads((корень / параметры['история_модели']).read_bytes())
            self.assertEqual('fum.подготовленный-коммит.5', подготовка['схема'])
            self.assertEqual(параметры['исполнитель'], история['задача'])
            текст = Path(параметры['сообщение']).read_text()
            self.assertIn('Первоначальное поручение корня:', текст)
            self.assertIn('model: gpt-6-astra\neffort: low', текст)
            self.assertTrue(текст.endswith('Codex-Thread-ID: ' + ЗАДАЧА + '\n'))
            self.assertNotIn('Исходные пользовательские команды:', текст)

    def test_чужая_будущая_цель_отказывает_до_истории_и_курсора(self):
        with фикстура() as (корень, _, параметры):
            параметры['разрешённые_цели'].append('общий.txt')
            with self.assertRaisesRegex(коммит.ОшибкаКоммита, 'област'):
                коммит.подготовить(параметры)
            self.assertFalse((корень / параметры['история_модели']).exists())
            self.assertFalse(Path(параметры['кэш_модели']).exists())
            self.assertFalse(Path(параметры['подготовка']).exists())

    def test_игнорируемая_история_отклоняется_до_записи_модели(self):
        with фикстура() as (корень, _, параметры):
            история = корень / параметры['история_модели']
            история.parent.mkdir(parents=True)
            (история.parent / '.gitignore').write_text('история-модели.json\n')
            with self.assertRaisesRegex(коммит.ОшибкаКоммита, 'игнорируем'):
                коммит.подготовить(параметры)
            self.assertFalse(история.exists())
            self.assertFalse(Path(параметры['кэш_модели']).exists())

    def test_подмены_контракта_не_оставляют_историю(self):
        with фикстура() as (корень, источник, параметры):
            варианты = [dict(назначение_sha256='f' * 64), dict(задача=параметры['исполнитель']),
                dict(кэш_модели=str(источник)), dict(история_модели='общий.txt'), dict(лишнее=True),
                dict(разрешённые_цели=параметры['разрешённые_цели'] + ['Память/события/А/а', 'Память/события/а/б'])]
            for замена in варианты:
                with self.subTest(поля=list(замена)):
                    with self.assertRaises(коммит.ОшибкаКоммита):
                        коммит.подготовить({**параметры, **замена})
                    self.assertFalse((корень / параметры['история_модели']).exists())
                    self.assertFalse(Path(параметры['кэш_модели']).exists())

    def test_управляющий_символ_будущей_истории_отказывает_до_записи(self):
        with фикстура() as (корень, источник, параметры):
            прежнее = параметры['история_модели']
            параметры['история_модели'] = прежнее.replace('история-модели', 'история\nмодели')
            параметры['разрешённые_цели'] = [параметры['история_модели'] if п == прежнее else п
                for п in параметры['разрешённые_цели']]
            with self.assertRaisesRegex(коммит.ОшибкаКоммита, 'Управляющий символ'):
                коммит.подготовить(параметры)
            self.assertFalse((корень / параметры['история_модели']).parent.exists())
            self.assertFalse(Path(параметры['кэш_модели']).exists())

    def test_неверный_корневой_UUID_запроса_отказывает_до_истории(self):
        with фикстура() as (корень, _, параметры):
            запрос = корень / параметры['запрос']
            текст = запрос.read_text()
            self.assertIn('Codex-Thread-ID: ' + ЗАДАЧА, текст)
            запрос.write_text(текст.replace('Codex-Thread-ID: ' + ЗАДАЧА,
                'Codex-Thread-ID: ' + параметры['исполнитель']))
            with self.assertRaisesRegex(коммит.ОшибкаКоммита, 'корневой trailer'):
                коммит.подготовить(параметры)
            self.assertFalse((корень / параметры['история_модели']).exists())
            self.assertFalse(Path(параметры['кэш_модели']).exists())

    def подготовить_готовность(self, корень, источник, параметры):
        коммит.подготовить(параметры)
        свежесть = importlib.import_module('свежесть_слоя')
        план = свежесть.подготовить(корень, параметры['исполнитель'], источник)
        свежесть.применить(корень, параметры['исполнитель'], источник, план)
        хранение.гит(корень, 'add', '.')
        with contextlib.redirect_stdout(io.StringIO()):
            код = коммит.отчёты.выполнить_запуск(корень, параметры['запрос'], 'Проверить байты слоя',
                'дочерний писатель', НОМЕР, 15, [sys.executable, '-c',
                "from pathlib import Path; assert Path('Память/события/данные.txt').read_text() == 'проверено\\n'"],
                класс_проверки='адресная', приёмочные_раунды=True)
            self.assertEqual(0, код)
            коммит.отчёты.выполнить_предпросмотр(корень, параметры['запрос'])
        хранение.гит(корень, 'add', '.')
        файл = Path(параметры['подготовка'])
        коммит.объявить_готовность(файл, [НОМЕР], 600)
        return файл

    def test_изменение_индекса_на_последнем_допуске_не_коммитится(self):
        with фикстура() as (корень, источник, параметры):
            файл = self.подготовить_готовность(корень, источник, параметры)
            допуск = коммит.передача()
            сверить = коммит.готовность.сверить
            проверить = допуск.проверить
            вооружён = False
            def после_готовности(*а, **к):
                nonlocal вооружён
                результат = сверить(*а, **к)
                вооружён = True
                return результат
            def поздняя_запись(*а, **к):
                nonlocal вооружён
                if вооружён:
                    вооружён = False
                    (корень / 'Память/события/данные.txt').write_text('не проверено\n')
                    хранение.гит(корень, 'add', 'Память/события/данные.txt')
                return проверить(*а, **к)
            with mock.patch.object(коммит.готовность, 'сверить', side_effect=после_готовности), \
                    mock.patch.object(допуск, 'проверить', side_effect=поздняя_запись):
                with self.assertRaisesRegex(коммит.ОшибкаКоммита, 'изменился после допуска'):
                    коммит.создать(файл, [НОМЕР])
            self.assertEqual(параметры['исходный_коммит'], хранение.гит(корень, 'rev-parse', 'HEAD').strip())
            self.assertFalse(Path(параметры['квитанция']).exists())

    def test_дочерний_коммит_и_восстановление_без_общих_записей(self):
        with фикстура() as (корень, источник, параметры):
            файл = self.подготовить_готовность(корень, источник, параметры)
            итог = коммит.создать(файл, [НОМЕР])
            self.assertEqual([параметры['исходный_коммит']], итог['родители'])
            self.assertEqual(итог, коммит.создать(файл, [НОМЕР]))
            self.assertFalse((корень / 'Журнал/README.md').exists())
            self.assertFalse((корень / 'Индексы').exists())
            self.assertEqual('', хранение.гит(корень, 'status', '--porcelain'))

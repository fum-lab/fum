"""Метки трёх начальных групп могут расти без расширения области инструкций."""
import copy
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-reyestr-planirovaniya' / 'scripts'))
import test_начального_контекста_писателя as фикстура


class ПроверкаВремениНачальныхИнструкций(unittest.TestCase):
    def setUp(сам):
        сам.основа = фикстура.ПроверкаНачальногоКонтекстаПисателя()
        сам.основа.setUp()
        сам.addCleanup(сам.основа.doCleanups)

    def записи(сам, метки):
        записи = сам.основа.записи()
        for номер, время in enumerate(метки, 2):
            записи[номер]['payload']['internal_chat_message_metadata_passthrough']['create_time'] = время
        return записи

    def test_неубывающие_метки_не_требуют_единого_такта(сам):
        случаи = [
            (1790630744.586182, 1790630744.586184, 1790630744.586184),
            (1790632459.441541, 1790632459.441542, 1790632459.441542),
            (1790632459.999999, 1790632460.000001, 1790632460.000002),
            (1790632459.441999, 1790632459.442001, 1790632459.442002),
            (1790632459.0, 1790632460.0, 1790632460.0),
        ]
        for метки in случаи:
            with сам.subTest(метки=метки):
                сам.assertEqual(фикстура.ХОД, сам.основа.прочитать(сам.записи(метки))[2])

    def test_уменьшение_на_каждом_переходе_отклоняется(сам):
        for метки in ((100.0, 99.0, 101.0), (100.0, 101.0, 100.0)):
            with сам.subTest(метки=метки), сам.assertRaises(ValueError):
                сам.основа.прочитать(сам.записи(метки))

    def test_нечисловые_неконечные_и_неположительные_метки_отклоняются(сам):
        for номер in range(3):
            for значение in (None, '100', True, float('nan'), float('inf'), -float('inf'), 0, -1):
                метки = [100.0, 101.0, 102.0]; метки[номер] = значение
                with сам.subTest(номер=номер, значение=значение), сам.assertRaises(ValueError):
                    сам.основа.прочитать(сам.записи(метки))

    def test_чужой_ход_по_прежнему_отклоняется(сам):
        for позиция in (2, 3, 4, 7):
            записи = сам.записи((100.0, 101.0, 102.0))
            данные = записи[позиция]['payload']
            (данные if позиция == 7 else данные['internal_chat_message_metadata_passthrough'])['turn_id'] = фикстура.ЗАДАЧА
            with сам.subTest(позиция=позиция), сам.assertRaises(ValueError):
                сам.основа.прочитать(записи)

    def test_неполный_повторный_и_переставленный_блок_отклоняется(сам):
        исходные = сам.записи((100.0, 101.0, 102.0))
        for вид in ('неполный', 'повторный', 'переставленный'):
            записи = copy.deepcopy(исходные)
            if вид == 'неполный':
                del записи[4]
            elif вид == 'повторный':
                записи.insert(5, copy.deepcopy(записи[4]))
            else:
                записи[2], записи[3] = записи[3], записи[2]
            with сам.subTest(вид=вид), сам.assertRaises(ValueError):
                сам.основа.прочитать(записи)

    def test_поздняя_инструкция_не_становится_новым_допуском(сам):
        for позиция in (5, 7, 9):
            записи = сам.записи((100.0, 101.0, 102.0))
            инструкция = copy.deepcopy(записи[4])
            инструкция['payload']['internal_chat_message_metadata_passthrough']['create_time'] = 103.0
            записи.insert(позиция, инструкция)
            with сам.subTest(позиция=позиция), сам.assertRaises(ValueError):
                сам.основа.прочитать(записи)


if __name__ == '__main__':
    unittest.main()

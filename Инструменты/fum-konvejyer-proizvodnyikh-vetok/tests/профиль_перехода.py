"""Стоимость локального перехода; подготовка фикстуры вне таймера."""
import argparse
import json
from pathlib import Path
import time

from test_перехода_координатора import переход_фикстура, хранение
import переход_координатора


def выполнить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--выход', required=True)
    аргументы = парсер.parse_args()
    выход = Path(аргументы.выход)
    if выход.exists():
        raise ValueError('Профиль не перезаписывается')
    измерения = []
    def измерить(имя, функция):
        начало = time.monotonic_ns()
        результат = функция()
        измерения.append({'стадия': имя, 'длительность_наносекунды': time.monotonic_ns() - начало})
        return результат
    with переход_фикстура() as (объект, _, пакет, _, _, _):
        до = объект.хранилище.прочитать()
        for _ in range(3):
            измерить('валидатор состояния v1', lambda: хранение.проверить_состояние(до, объект.хранилище.общий))
        план = измерить('предпросмотр', lambda: переход_координатора.предпросмотр(объект, пакет))
        принятый = измерить('применение', lambda: переход_координатора.перейти(объект, пакет, план['sha256']))
        байты = объект.хранилище.путь.read_bytes()
        повтор = измерить('точный повтор', lambda: переход_координатора.перейти(объект, пакет, план['sha256']))
        if принятый != план or повтор != план or объект.хранилище.путь.read_bytes() != байты:
            raise ValueError('Повтор изменил состояние')
        после = объект.хранилище.прочитать()
        for _ in range(3):
            измерить('валидатор состояния v2', lambda: хранение.проверить_состояние(после, объект.хранилище.общий))
        результат = {'схема': 'fum.профиль-перехода-координатора.1',
            'граница': 'Открытая временная Git-фикстура, синтетический JSONL; без Desktop и сети. Подготовка вне таймера.',
            'история_сохранена': до['этапы'] == после['этапы'] and до['попытки'] == после['попытки'],
            'повтор_без_записи': True, 'измерения': измерения}
    выход.parent.mkdir(parents=True, exist_ok=True)
    with выход.open('x') as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2)
        поток.write('\n')
    print(json.dumps(результат, ensure_ascii=False))


if __name__ == '__main__':
    выполнить()

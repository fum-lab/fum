"""Профиль закрытия .7 с сохранёнными байтами или проверенным коммитом H."""
import argparse
from contextlib import ExitStack
import hashlib
import json
from pathlib import Path
import statistics
import time
from unittest import mock

from фикстура_смешанного_создания import смешанное_создание, хранение
import завершение_смешанного_создания as закрытие
import снимок_области
import терминал_запуска


def измерить():
    измерения = []
    for с_коммитом in (False, True):
        фазы = []

        def серия(имя, число, действие):
            времена, результаты = [], []
            for _ in range(число):
                начало = time.perf_counter_ns()
                результаты.append(действие())
                времена.append(time.perf_counter_ns() - начало)
            assert all(р == результаты[0] for р in результаты)
            фазы.append({'стадия': имя, 'вызовов': число, 'наносекунды': времена,
                         'минимум': min(времена), 'медиана': int(statistics.median(времена)),
                         'максимум': max(времена)})
            return результаты[0]

        начало = time.perf_counter_ns()
        with смешанное_создание(с_коммитом=с_коммитом) as (_, объект, пакет, план, вход, _, дети):
            подготовка = time.perf_counter_ns() - начало
            H, задача_H, источник_H = дети['события']
            S, _, источник_S = дети['сообщения']
            база = пакет['постановка']['коммит']
            назначение = хранение.разобрать(хранение.гит(
                объект.корень, 'show', база + ':' + пакет['назначение'], сырые=True))
            области = ['Память/события/', назначение['журналы']['события']]
            снимок_H = снимок_области.снимок(H, задача_H, база, области)
            refs = хранение.гит(H, 'show-ref')
            до = объект.хранилище.прочитать()
            байты_до = объект.хранилище.путь.read_bytes()
            просмотр = серия('предпросмотр', 3, lambda: закрытие.предпросмотр(объект, вход))
            assert объект.хранилище.путь.read_bytes() == байты_до
            итог = серия('повторная сверка и запись под замком', 1,
                         lambda: закрытие.завершить(объект, вход, просмотр['sha256']))
            assert итог == просмотр
            после = объект.хранилище.прочитать()
            assert после['приёмы'].pop(терминал_запуска.ключ(план['запуск'])) == итог and после == до
            байты_после = объект.хранилище.путь.read_bytes()
            цели = [(закрытие.нативные_вызовы, 'прочитать'), (закрытие.сохранённый_писатель, 'проверить'),
                    (закрытие.закоммиченный_писатель, 'проверить'), (закрытие.остановка_ребёнка, 'проверить'),
                    (закрытие.возобновления_до_записи, 'проверить'), (закрытие, '_ветки'),
                    (закрытие, '_снимок_корня')]
            with ExitStack() as стек:
                запреты = [стек.enter_context(mock.patch.object(м, имя,
                    side_effect=AssertionError('Исторический повтор читает живое основание')))
                    for м, имя in цели]
                assert серия('исторический повтор без живых чтений', 7,
                    lambda: закрытие.завершить(объект, вход, просмотр['sha256'])) == итог
                for запрет in запреты:
                    запрет.assert_not_called()
            assert объект.хранилище.путь.read_bytes() == байты_после
            assert снимок_области.снимок(H, задача_H, база, области) == снимок_H
            assert хранение.гит(H, 'show-ref') == refs
            assert хранение.гит(S, 'rev-parse', '--symbolic-full-name', 'HEAD').strip() == 'HEAD'
            assert not хранение.гит(S, 'status', '--porcelain')
            измерения.append({'вид_H': итог['слои']['события']['вид'],
                'подготовка_фикстуры_наносекунды': подготовка, 'фазы': фазы,
                'размеры_байтов': {'JSONL_H': источник_H.stat().st_size,
                    'JSONL_S': источник_S.stat().st_size, 'JSONL_корня': вход['источник']['граница'],
                    'реестр_до': len(байты_до), 'реестр_после': len(байты_после)}})
    каталог = Path(__file__).resolve().parents[1]
    пути = set(закрытие.КОД) | {Path(__file__).resolve()}
    пути |= {каталог / 'tests' / имя for имя in ('фикстура_смешанного_создания.py',
        'фикстура_барьера_запуска.py', 'фикстура_дочернего_коммита.py',
        'фикстура_новых_веток.py', 'фикстура_остановленного_поколения.py')}
    return {'схема': 'fum.профиль-смешанного-создания.1', 'измерения': измерения,
        'исходники_sha256': {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in sorted(пути)},
        'граница': 'Настоящие временные Git-дети и синтетический Native JSONL; Desktop, сеть и большой живой реестр исключены. '
            'Подготовка измерена отдельно и включает штатное создание H в соответствующем варианте. '
            'Совпадение исполняемого checkout с C подменено только фикстурой. '
            'Запись терминала измерена один раз на вариант. Семь исторических повторов запрещают семь видов живого чтения. '
            'Сравнение вариантов не доказывает ускорения Git, Desktop или общего smoke-check.'}


if __name__ == '__main__':
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path, required=True)
    аргументы = разбор.parse_args()
    результат = измерить()
    with аргументы.выход.open('x', encoding='utf-8') as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2)
        поток.write('\n')
    print(json.dumps(результат, ensure_ascii=False))

#!/usr/bin/env python3
"""Воспроизводимый профиль чистого чтения открытых рамок отказа."""
import hashlib
import json
from pathlib import Path
import statistics
import time

from test_отказа_нативного_приёма import образец, строка
from test_отказа_сохранённого_приёма import сохранённый
import отказ_нативного_приёма as прямой
import отказ_сохранённого_приёма as сохранённый_канал


def измерить(функция, аргументы):
    повторы = 1000
    замеры = []
    for _ in range(7):
        начало = time.perf_counter_ns()
        for _ in range(повторы):
            функция(*аргументы)
        замеры.append(time.perf_counter_ns() - начало)
    return {'повторы': повторы, 'раунды_наносекунды': замеры,
            'медиана_наносекунд_на_вызов': statistics.median(замеры) / повторы}


def выполнить():
    м, с, ц = образец()
    прямые = (м + строка(с), ц)
    м, с, ц, канал, артефакт = сохранённый()
    обёрнутые = (м + строка(с), ц, канал, артефакт)
    return {'схема': 'fum.профиль-первичного-отказа.1',
        'область': 'чистая функция и цикл Python; открытая рамка; без чтения диска, Git, JSONL всей задачи и LLM',
        'исходники': {Path(м.__file__).name: hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
                     for м in (прямой, сохранённый_канал)},
        'байты_фикстуры': {'прямой': len(прямые[0]), 'сохранённый': len(обёрнутые[0]), 'канал': len(канал)},
        'прямой': измерить(прямой.проверить, прямые),
        'сохранённый': измерить(сохранённый_канал.проверить, обёрнутые)}


if __name__ == '__main__':
    print(json.dumps(выполнить(), ensure_ascii=False, sort_keys=True))

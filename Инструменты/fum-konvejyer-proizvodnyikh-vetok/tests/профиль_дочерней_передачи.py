"""Один синтетический проход передачи: установка, подготовка, коммит, повтор."""
import argparse
import contextlib
import hashlib
import io
import json
from pathlib import Path
import sys
import time
from unittest import mock

from фикстура_дочернего_коммита import фикстура, коммит, НОМЕР
from test_запуска_слоёв import хранение
import журнал_слоя
import свежесть_слоя


def выполнить(выход):
    фазы = []
    def измерить(имя, операция, *а, **к):
        начало = time.perf_counter_ns()
        результат = операция(*а, **к)
        фазы.append({'стадия': имя, 'наносекунды': time.perf_counter_ns() - начало})
        return результат
    установить = журнал_слоя.установить
    with mock.patch.object(журнал_слоя, 'установить',
            side_effect=lambda *а, **к: измерить('установка пары', установить, *а, **к)), \
            фикстура() as (корень, источник, параметры):
        измерить('подготовка коммита', коммит.подготовить, параметры)
        план = измерить('план собственной свежести', свежесть_слоя.подготовить,
            корень, параметры['исполнитель'], источник)
        измерить('применение собственной свежести', свежесть_слоя.применить,
            корень, параметры['исполнитель'], источник, план)
        хранение.гит(корень, 'add', '.')
        with contextlib.redirect_stdout(io.StringIO()):
            код = измерить('адресная проверка с учётом в отчёте', коммит.отчёты.выполнить_запуск,
                корень, параметры['запрос'], 'Проверить байты профиля', 'дочерний писатель', НОМЕР,
                15, [sys.executable, '-c', "from pathlib import Path; assert Path('Память/события/данные.txt').read_text() == 'проверено\\n'"],
                класс_проверки='адресная', приёмочные_раунды=True)
            if код != 0:
                raise RuntimeError('Не прошла адресная проверка профиля')
            коммит.отчёты.выполнить_предпросмотр(корень, параметры['запрос'])
        хранение.гит(корень, 'add', '.')
        подготовка = Path(параметры['подготовка'])
        измерить('объявление готовности', коммит.объявить_готовность, подготовка, [НОМЕР], 600)
        первый = измерить('создание коммита с допусками', коммит.создать, подготовка, [НОМЕР])
        повтор = измерить('восстановление квитанции', коммит.создать, подготовка, [НОМЕР])
        if первый != повтор or хранение.гит(корень, 'status', '--porcelain'):
            raise RuntimeError('Повтор изменил результат или оставил записи')
        внутренний = json.loads(Path(параметры['квитанция']).read_bytes())['профиль']
    репозиторий = Path(__file__).resolve().parents[3]
    собственные = list(Path(__file__).parents[1].joinpath('scripts').glob('*.py'))
    связанные = [Path(__file__), Path(__file__).with_name('фикстура_дочернего_коммита.py'),
        Path(__file__).with_name('test_области_писателя.py'), Path(__file__).with_name('test_запуска_слоёв.py'),
        Path(коммит.__file__), Path(коммит.готовность.__file__)]
    результат = {'схема': 'fum.профиль-дочерней-передачи.1', 'фазы': фазы,
        'профиль_создания': внутренний,
        'граница': 'Один последовательный проход открытой Git-фикстуры. Подготовка репозитория и раннего подтверждения вне замеров. Фикстура подменяет проверку расположения исполняемого кода. Нет Desktop, сети, push, общей интеграции или измерения на полном FUM.',
        'повтор_совпал': True,
        'исходники': {п.relative_to(репозиторий).as_posix(): hashlib.sha256(п.read_bytes()).hexdigest()
            for п in sorted(set(собственные + связанные))}}
    with Path(выход).open('x') as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2)
        поток.write('\n')
    print(json.dumps({'фазы': фазы, 'повтор_совпал': True}, ensure_ascii=False))


if __name__ == '__main__':
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', required=True)
    выполнить(разбор.parse_args().выход)

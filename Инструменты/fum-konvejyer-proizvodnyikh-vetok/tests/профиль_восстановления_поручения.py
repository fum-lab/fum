"""Стоимость чистого предложения на открытых строковых фикстурах."""
import argparse
import hashlib
import json
from pathlib import Path
import statistics
import time

from test_восстановления_поручения import документ, МЕТКА, ПОРУЧЕНИЕ, восстановление


def измерить():
    измерения = []
    for объём in (0, 262144):
        поручение = ПОРУЧЕНИЕ + ('я' * объём + '\n').encode('utf-8')
        целое = документ(поручение)
        повреждённое = документ(поручение.replace(МЕТКА.encode('utf-8'), b'', 1))
        for вид, вход in (('восстановление', повреждённое), ('повтор', целое)):
            длительности = []
            for _ in range(25):
                начало = time.perf_counter_ns()
                результат, свидетельство = восстановление.предложить(вход, поручение)
                длительности.append(time.perf_counter_ns() - начало)
                if результат != целое or свидетельство['разрешение_записи']:
                    raise AssertionError('Предложение не совпало с открытым оригиналом')
            измерения.append({'вид': вид, 'байтов': len(вход), 'повторов': len(длительности),
                'медиана_наносекунды': statistics.median(длительности),
                'минимум_наносекунды': min(длительности), 'максимум_наносекунды': max(длительности),
                'оригинал_восстановлен': True})
    модули = {'преобразование': восстановление, 'ограды': восстановление.ограды_цитат,
              'каркас': восстановление.каркас}
    return {'схема': 'fum.профиль-восстановления-поручения.1',
        'исходники_sha256': {имя: hashlib.sha256(Path(модуль.__file__).read_bytes()).hexdigest()
                            for имя, модуль in модули.items()},
        'измерения': измерения,
        'граница': 'Преобразование bytes в памяти, без импорта модулей, диска, Git, проверки происхождения и допуска записи.'}


if __name__ == '__main__':
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--выход', required=True, type=Path)
    параметры = парсер.parse_args()
    итог = измерить()
    with параметры.выход.open('x', encoding='utf-8') as файл:
        файл.write(json.dumps(итог, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(итог, ensure_ascii=False))

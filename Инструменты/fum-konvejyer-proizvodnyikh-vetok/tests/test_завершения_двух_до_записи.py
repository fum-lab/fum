    def test_сдвиг_между_проверкой_под_замком_и_терминалом_также_отклоняется(сам):
        for вид in ('ребёнок', 'корень', 'ref'):
            with сам.subTest(вид=вид), два_до_записи() as (корень, объект, план, вход, _, дети):
                модуль = сам.модуль(); итог = модуль.предпросмотр(объект, вход); исходная = модуль._план
                def сдвинуть(*а):
                    результат = исходная(*а)
                    if вид == 'ref': хранение.гит(корень, 'update-ref', план['описание']['слои'][0]['ветка'], вход['координатор']['HEAD'])
                    else:
                        путь = дети['сообщения'][2] if вид == 'ребёнок' else __import__('pathlib').Path(вход['источник']['путь'])
                        with путь.open('ab') as поток: поток.write(строка({'type': 'event_msg', 'payload': {'type': 'task_started'}}))
                    return результат
                до = объект.хранилище.путь.read_bytes()
                with mock.patch.object(модуль, '_план', side_effect=сдвинуть), сам.assertRaises(ValueError):
                    модуль.завершить(объект, вход, итог['sha256'])
                сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_старый_терминал_не_заменяется_новым(сам):
        with два_до_записи() as (_, объект, план, вход, _, _):
            модуль = сам.модуль(); итог = модуль.предпросмотр(объект, вход)
            итог['схема'] = модуль.терминал_запуска.СХЕМА
            del итог['sha256']; итог['sha256'] = хранение.хэш(итог)
            with объект.хранилище.изменить() as состояние:
                состояние['приёмы'][модуль.терминал_запуска.ключ(план['запуск'])] = итог
            with сам.assertRaisesRegex(ValueError, 'терминал'): модуль.предпросмотр(объект, вход)



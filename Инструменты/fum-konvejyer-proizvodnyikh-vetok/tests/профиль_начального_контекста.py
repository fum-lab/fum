"""Профиль полного читателя: открытая фикстура либо два остановленных Native."""
import argparse
import json
from pathlib import Path
import statistics
import time
from unittest.mock import patch

from test_начального_контекста_писателя import ПроверкаНачальногоКонтекстаПисателя, поток


def измерить(действие, число):
    замеры = []
    for _ in range(число):
        начало = time.monotonic_ns()
        действие()
        замеры.append(time.monotonic_ns() - начало)
    return {'повторы': число, 'медиана_ns': int(statistics.median(замеры)),
        'минимум_ns': min(замеры), 'максимум_ns': max(замеры)}


def выполнить():
    парсер = argparse.ArgumentParser()
    парсер.add_argument('--вход')
    парсер.add_argument('--база')
    парсер.add_argument('--ожидание-события')
    парсер.add_argument('--ожидание-сообщения')
    парсер.add_argument('--повторы', type=int, default=3)
    аргументы = парсер.parse_args()
    if not 1 <= аргументы.повторы <= 10:
        raise ValueError('Профиль ограничен десятью повторениями')
    количество = 0
    исходный = поток.хранение.гит

    def учесть(*позиционные, **именованные):
        nonlocal количество
        количество += 1
        return исходный(*позиционные, **именованные)

    результаты = {}
    with patch.object(поток.хранение, 'гит', учесть):
        if аргументы.вход:
            вход = json.loads(Path(аргументы.вход).read_bytes())
            if вход['схема'] != 'fum.завершение-неудачного-запуска.8' or not аргументы.база:
                raise ValueError('Нужны первоначальная база и вход завершения .8')
            for имя, адрес in [('события', аргументы.ожидание_события),
                    ('сообщения', аргументы.ожидание_сообщения)]:
                слой = вход['слои'][имя]
                ожидание = {'ответ': json.loads(Path(адрес).read_bytes())}

                def прочитать():
                    поток.прочитать(слой['источник'], слой['задача'], слой['корень'],
                        аргументы.база, 'gpt-6-sol', 'ultra', ожидание)

                результаты[имя] = {'байты': слой['источник']['граница'],
                    **измерить(прочитать, аргументы.повторы)}
            граница = 'полный читатель двух настоящих остановленных потоков; без Git, сети и записи'
        else:
            проверка = ПроверкаНачальногоКонтекстаПисателя()
            проверка.setUp()
            try:
                записи = проверка.записи()
                результаты['открытая_фикстура'] = измерить(lambda: проверка.прочитать(записи), аргументы.повторы)
            finally:
                проверка.doCleanups()
            граница = 'открытая фикстура: запись временного JSONL и полный читатель; без Git и сети'
    if количество:
        raise ValueError('Профиль первичного потока неожиданно вызвал Git')
    return {'схема': 'fum.профиль-начального-контекста.1', 'граница': граница,
        'вызовов_гита': количество, 'результаты': результаты}


if __name__ == '__main__':
    print(json.dumps(выполнить(), ensure_ascii=False))

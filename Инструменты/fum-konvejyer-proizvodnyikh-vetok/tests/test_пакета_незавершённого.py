"""Сохраняются независимые версии рабочего файла и stage-0."""
from contextlib import contextmanager
import copy
import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import пакет_незавершённого as пакет

ЗАДАЧА = '11111111-1111-4111-8111-111111111111'
КАТАЛОГИ = ['Память/слой/', 'Журнал/слой/']


def гит(корень, *аргументы, **прочее):
    return subprocess.check_output(['git', '--no-optional-locks', '-C', str(корень), *аргументы], **прочее)


@contextmanager
def фикстура():
    with tempfile.TemporaryDirectory() as временный:
        корень = Path(временный).resolve()
        гит(корень, 'init', '-q', '-b', 'codex/слой')
        гит(корень, 'config', 'user.name', 'Открытая фикстура')
        гит(корень, 'config', 'user.email', 'fixture@example.invalid')
        (корень / 'Память/слой').mkdir(parents=True)
        (корень / 'Память/слой/данные').write_bytes(b'base\n')
        (корень / 'Память/слой/удалённый').write_bytes(b'base removed\n')
        (корень / 'README.md').write_text('Открытая база\n')
        гит(корень, 'add', '--', '.')
        гит(корень, 'commit', '-qm', 'База')
        база = гит(корень, 'rev-parse', 'HEAD').decode().strip()
        yield корень, база


class ПроверкаПакетаНезавершённого(unittest.TestCase):
    def test_индекс_рабочий_файл_удаление_и_новый_бинарник(сам):
        with фикстура() as (корень, база):
            путь = корень / 'Память/слой/данные'
            путь.write_bytes(b'index\x00\xff\n')
            гит(корень, 'add', '--', 'Память/слой/данные')
            путь.write_bytes('Рабочие байты — ё🙂\n'.encode())
            путь.chmod(0o755)
            гит(корень, 'rm', '-q', '--', 'Память/слой/удалённый')
            (корень / 'Память/слой/новый').write_bytes(b'\x00\xff\r\n')
            до = гит(корень, 'ls-files', '--stage', '-z')
            план, данные = пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ)
            сам.assertEqual(до, гит(корень, 'ls-files', '--stage', '-z'))
            сам.assertFalse(план['разрешение_установки'])
            строка = план['файлы']['Память/слой/данные']
            сам.assertEqual(данные[строка['индекс']['sha256']], b'index\x00\xff\n')
            сам.assertEqual(данные[строка['рабочий']['sha256']], путь.read_bytes())
            сам.assertEqual(строка['индекс']['режим'], '100644')
            сам.assertEqual(строка['рабочий']['режим'], 0o755)
            сам.assertIsNone(план['файлы']['Память/слой/новый']['индекс'])
            сам.assertEqual(план['файлы']['Память/слой/удалённый'], {'индекс': None, 'рабочий': None})
            сам.assertEqual(пакет.проверить(план, данные), план['sha256'])

    def test_повтор_и_общий_объект_для_одинаковых_байтов(сам):
        with фикстура() as (корень, база):
            (корень / 'Память/слой/данные').write_bytes(b'one copy\n')
            гит(корень, 'add', '--', 'Память/слой/данные')
            план, данные = пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ)
            сам.assertEqual(len(данные), 1)
            сам.assertEqual((план, данные), пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ))
            повреждённые = dict(данные)
            повреждённые[next(iter(данные))] += b'changed'
            with сам.assertRaises(ValueError):
                пакет.проверить(план, повреждённые)
            with сам.assertRaises(ValueError):
                пакет.проверить(план, {})
            лишние = dict(данные); лишние[hashlib.sha256(b'extra').hexdigest()] = b'extra'
            with сам.assertRaises(ValueError):
                пакет.проверить(план, лишние)

    def test_удаление_индекса_и_рабочего_файла_независимы(сам):
        with фикстура() as (корень, база):
            (корень / 'Память/слой/данные').unlink()
            гит(корень, 'rm', '--cached', '-q', '--', 'Память/слой/удалённый')
            план, данные = пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ)
            первая = план['файлы']['Память/слой/данные']
            сам.assertIsNone(первая['рабочий'])
            сам.assertEqual(данные[первая['индекс']['sha256']], b'base\n')
            вторая = план['файлы']['Память/слой/удалённый']
            сам.assertIsNone(вторая['индекс'])
            сам.assertEqual(данные[вторая['рабочий']['sha256']], b'base removed\n')

    def test_сдвиг_рабочих_байтов_во_время_чтения_отклоняется(сам):
        with фикстура() as (корень, база):
            путь = корень / 'Память/слой/данные'; путь.write_bytes(b'before\n')
            настоящее = пакет.снимок_области.снимок
            число = 0
            def снимок(*аргументы):
                nonlocal число
                число += 1
                if число == 2:
                    путь.write_bytes(b'after\n')
                return настоящее(*аргументы)
            with mock.patch.object(пакет.снимок_области, 'снимок', side_effect=снимок):
                with сам.assertRaisesRegex(ValueError, 'сдвинул'):
                    пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ)

    def test_чужой_путь_или_ссылка_отклоняется(сам):
        with фикстура() as (корень, база):
            (корень / 'README.md').write_text('Чужое изменение\n')
            with сам.assertRaises(ValueError):
                пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ)
            (корень / 'README.md').write_text('Открытая база\n')
            (корень / 'Память/слой/ссылка').symlink_to(корень / 'README.md')
            with сам.assertRaises(ValueError):
                пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ)

    def test_подмена_oid_при_верных_байтах_отклоняется(сам):
        with фикстура() as (корень, база):
            (корень / 'Память/слой/данные').write_bytes(b'index\n')
            гит(корень, 'add', '--', 'Память/слой/данные')
            план, данные = пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ)
            подмена = copy.deepcopy(план)
            подмена['файлы']['Память/слой/данные']['индекс']['oid'] = 'a' * 40
            подмена['sha256'] = пакет.хранение.хэш({к: в for к, в in подмена.items() if к != 'sha256'})
            with сам.assertRaisesRegex(ValueError, 'OID'):
                пакет.проверить(подмена, данные)

    def test_неполный_снимок_не_принимается_даже_с_новым_хэшем(сам):
        with фикстура() as (корень, база):
            план, данные = пакет.собрать(корень, ЗАДАЧА, база, КАТАЛОГИ)
            for раздел, поле in [('владелец', 'ref'), ('владелец', 'задача'),
                                 (None, 'индекс_sha256'), ('границы', 'HEAD_индекс')]:
                with сам.subTest(раздел=раздел, поле=поле):
                    подмена = copy.deepcopy(план)
                    цель = подмена['снимок'] if раздел is None else подмена['снимок'][раздел]
                    del цель[поле]
                    подмена['sha256'] = пакет.хранение.хэш({к: в for к, в in подмена.items() if к != 'sha256'})
                    with сам.assertRaises(ValueError):
                        пакет.проверить(подмена, данные)


if __name__ == '__main__':
    unittest.main()

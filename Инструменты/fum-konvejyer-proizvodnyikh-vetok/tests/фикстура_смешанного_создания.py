"""Настоящие Git-дети .7: назначенный H и реально созданный чистый S."""
from contextlib import contextmanager
import copy
import json
import os
from pathlib import Path
from unittest import mock

import фикстура_барьера_запуска as барьер
from фикстура_двух_до_записи import транспорт, первичный_вызов, обновить_источники
from фикстура_дочернего_коммита import подготовить_передачу, коммит, НОМЕР
from test_запуска_слоёв import строка, хранение, ЗАДАЧА
from test_завершения_запуска import граница
import пакет_незавершённого
import хранилище_незавершённого


def базовые_инструменты(корень):
    путь = корень / 'Инструменты/реестр-системных-приложений-и-инструментов.md'
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text('# Инструменты\n\nОткрытая фикстура Python и Git.\n')


def _ожидание(задача, ход):
    return {'content': [{'type': 'text', 'text': json.dumps({'polls': [
        {'thread': {'id': задача, 'status': {'type': 'idle'}},
         'latestTurn': {'id': ход, 'status': 'completed', 'error': None}}
    ]})}], 'isError': False}


@contextmanager
def смешанное_создание(*, с_коммитом=False):
    исходная_строка = строка
    def с_временем(запись):
        return исходная_строка({'timestamp': '2026-09-23T09:00:00Z', **запись})
    with mock.patch.dict(os.environ, CODEX_THREAD_ID=ЗАДАЧА), \
            mock.patch.object(барьер, 'строка', side_effect=с_временем), \
            барьер.запуск(подготовить_базу=базовые_инструменты) as (корень, объект, пакет, план):
        H, задача_H, источник_H, допуск_H, записи_H, события = барьер.первый(
            корень, объект, пакет, план, писатель=True)
        база = пакет['постановка']['коммит']
        назначение = хранение.разобрать(хранение.гит(
            корень, 'show', база + ':' + пакет['назначение'], сырые=True))
        допуск_S = объект.допустить(пакет, 'сообщения', источник_первого_ребёнка=источник_H)
        задача_S = '00000000-0000-4000-8000-000000000002'
        ход_S = '00000000-0000-4000-8001-000000000002'
        S = корень.parent / 'второй-ребёнок'
        хранение.гит(корень, 'worktree', 'add', '--detach', str(S), база)
        ответ_S = {'content': [{'type': 'text', 'text': json.dumps({'threadId': задача_S})}], 'isError': False}
        объект.сохранить(план['запуск'], 'сообщения', допуск_S['попытка'], ответ_S)
        политика_S = {**copy.deepcopy(барьер.ПОЛИТИКА), 'approval_policy': 'on-request',
                      'sandbox_policy': {'type': 'workspace-write'}}
        источник_S = корень.parent / 'второй.jsonl'
        записи_S = [
            {'type': 'session_meta', 'payload': {'id': задача_S, 'cwd': str(S), 'git': {'commit_hash': база}}},
            {'type': 'turn_context', 'payload': {'cwd': str(S), 'model': 'gpt-6-sol', 'effort': 'ultra', **политика_S}},
            {'type': 'response_item', 'payload': {'type': 'function_call_output', 'name': 'create_thread',
                                                'output': транспорт(допуск_S['аргументы']['prompt'])}},
            {'type': 'event_msg', 'payload': {'type': 'task_complete', 'turn_id': ход_S}},
        ]
        источник_S.write_bytes(b''.join(с_временем(з) for з in записи_S))
        слой_H = {'попытка': допуск_H['попытка'], 'задача': задача_H, 'корень': str(H),
                  'источник': граница(источник_H)}
        if с_коммитом:
            from test_дочернего_коммита import ПроверкаДочернегоКоммита
            with mock.patch.dict(os.environ, CODEX_THREAD_ID=задача_H), \
                    mock.patch.object(коммит.готовность, 'КОРЕНЬ_СОСТОЯНИЯ', корень.parent / 'готовность-H'):
                параметры = подготовить_передачу(H, задача_H, источник_H, пакет, назначение)
                готовность = ПроверкаДочернегоКоммита().подготовить_готовность(H, источник_H, параметры)
                коммит.создать(готовность, [НОМЕР])
            def свидетельство(путь):
                путь = Path(путь)
                return {'путь': str(путь), 'sha256': коммит.хэш(путь.read_bytes())}
            слой_H.update(вид='остановлен-с-коммитом',
                подготовка=свидетельство(параметры['подготовка']),
                квитанция=свидетельство(параметры['квитанция']))
        else:
            путь = H / 'Память/события/поток.jsonl'
            путь.parent.mkdir(parents=True)
            путь.write_bytes(b'index\x00\xff\n')
            хранение.гит(H, 'add', '--', 'Память/события/поток.jsonl')
            путь.write_bytes(b'working\x00\xff\n')
            описание, данные = пакет_незавершённого.собрать(
                H, задача_H, база, ['Память/события/', назначение['журналы']['события']])
            архив = корень.parent / 'сохранение-H'
            хранилище_незавершённого.сохранить(архив, описание, данные)
            слой_H['пакет'] = {'путь': str(архив), 'sha256': описание['sha256']}
        # Финальный H-ход наблюдается после создания коммита/сохранения.
        ход_H = '00000000-0000-4000-8002-000000000001'
        записи_H[-1]['payload']['turn_id'] = ход_H
        источник_H.write_bytes(b''.join(с_временем(з) for з in записи_H))
        события = события[:2] + [
            первичный_вызов('create_thread', 'создать-сообщения', допуск_S['аргументы'], ответ_S, 20),
            первичный_вызов('wait_threads', 'ожидать-H', {'targets': [{'threadId': задача_H}]},
                           _ожидание(задача_H, ход_H), 30),
            первичный_вызов('wait_threads', 'ожидать-S', {'targets': [{'threadId': задача_S}]},
                           _ожидание(задача_S, ход_S), 40),
        ]
        хранение.гит(корень, 'commit', '--allow-empty', '-qm', 'Открытая фикстура нового координатора')
        родитель = корень.parent / 'родитель-смешанный.jsonl'
        родитель.touch()
        вход = {'схема': 'fum.завершение-неудачного-запуска.7', 'запуск': план['запуск'],
            'план_sha256': план['sha256'], 'координатор': объект.хранилище._наблюдать_владельца(),
            'источник': {'путь': str(родитель)}, 'ожидания': {задача_H: 'ожидать-H', задача_S: 'ожидать-S'},
            'слои': {'события': слой_H, 'сообщения': {'вид': 'остановлен-до-записи',
                'попытка': допуск_S['попытка'], 'задача': задача_S, 'корень': str(S),
                'источник': граница(источник_S)}}, 'возобновления': {},
            'свидетельство_координатора': {'задача': ЗАДАЧА, 'единственный_координатор': True,
                'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}}
        обновить_источники(вход, события)
        yield корень, объект, пакет, план, вход, события, {'события': (H, задача_H, источник_H),
                                                       'сообщения': (S, задача_S, источник_S)}

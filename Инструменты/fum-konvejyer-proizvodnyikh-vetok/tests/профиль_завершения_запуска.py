"""Профиль конечного перехода; подготовка Git исключена, Desktop не вызывается."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from test_завершения_запуска import пилот
import завершение_запуска


def измерить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--выход", required=True)
    аргументы = парсер.parse_args()
    фазы = []
    def вызов(имя, действие):
        начало = time.perf_counter_ns()
        результат = действие()
        фазы.append({"стадия": имя, "наносекунды": time.perf_counter_ns() - начало})
        return результат
    with пилот() as (_, объект, _, _, вход, _, _):
        план = вызов("предпросмотр", lambda: завершение_запуска.предпросмотр(объект, вход))
        результат = вызов("проверка под замком и запись", lambda: завершение_запуска.завершить(объект, вход, план["sha256"]))
        повтор = вызов("идемпотентный повтор", lambda: завершение_запуска.завершить(объект, вход, план["sha256"]))
        assert план == результат == повтор
        размер = вход["источник"]["граница"]
    каталог = Path(__file__).resolve().parents[1]
    пути = [каталог / "scripts" / имя for имя in ("нативные_вызовы.py", "остановка_ребёнка.py", "терминал_запуска.py", "завершение_запуска.py", "запуск_слоёв.py", "запустить-слои.py")]
    результат = {"схема": "fum.профиль-завершения-запуска.1", "фазы": фазы, "байтов_источника": размер,
        "граница": "Открытая временная Git-фикстура; подготовка исключена. Допуск совпадения checkout кода подменён. Desktop и сеть не вызываются; большой JSONL измеряется отдельно.",
        "исходники": {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in пути}}
    with Path(аргументы.выход).open("x") as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2)
        поток.write("\n")
    print(json.dumps(результат, ensure_ascii=False))


if __name__ == "__main__":
    измерить()

"""Собственное ожидание закрывает только последнюю отправку своему ребёнку."""
import copy
import sys
from pathlib import Path
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
sys.path.insert(0, str(Path(__file__).resolve().parents[2]
                     / 'fum-reyestr-planirovaniya' / 'scripts'))
import ожидания_обратного_приёма as ожидания
import раздельные_ожидания as прежние

H = '11111111-1111-4111-8111-111111111111'
S = '22222222-2222-4222-8222-222222222222'


def вызов(имя, номер, ребёнок, позиция, начало, конец):
    аргументы = ({'targets': [{'threadId': ребёнок}]} if имя == 'wait_threads'
                 else {'threadId': ребёнок, 'prompt': 'Адресный приём'})
    return {'инструмент': имя, 'id': номер, 'аргументы': аргументы,
            'источник': {'начало': позиция, 'конец': позиция + 10},
            'интервал': {'начало_мс': начало, 'конец_мс': конец}}


def последовательность():
    send_h = вызов('send_message_to_thread', 'send-H', H, 100, 1, 2)
    wait_h = вызов('wait_threads', 'wait-H', H, 200, 3, 4)
    send_s = вызов('send_message_to_thread', 'send-S', S, 300, 5, 6)
    wait_s = вызов('wait_threads', 'wait-S', S, 400, 7, 8)
    return {'схема': 'fum.наблюдённые-вызовы-запуска.2',
            'источник': {'начало': 20}, 'начальная_граница': 20,
            'вызовы': [], 'возобновления': [send_h, send_s],
            'ожидания': [wait_h, wait_s]}


class ПроверкаОжиданийОбратногоПриёма(unittest.TestCase):
    def setUp(self):
        self.номера = {H: 'wait-H', S: 'wait-S'}
        self.отправки = {H: 'send-H', S: 'send-S'}

    def проверить(self, нативный):
        return ожидания.проверить(нативный, self.номера, self.отправки)

    def test_последовательные_собственные_ожидания_без_ослабления_прежнего_контракта(self):
        нативный = последовательность()
        до = copy.deepcopy(нативный)
        выбранные = self.проверить(нативный)
        self.assertEqual(self.номера, {к: в['id'] for к, в in выбранные.items()})
        self.assertEqual(до, нативный)
        with self.assertRaisesRegex(ValueError, 'до завершения воздействия'):
            прежние.проверить(нативный, self.номера, [H, S])

    def test_ожидание_до_своей_отправки_или_перекрытие_не_закрывают_приём(self):
        for поле, значение in [('источник', {'начало': 90, 'конец': 99}),
                               ('интервал', {'начало_мс': 2, 'конец_мс': 4})]:
            with self.subTest(поле=поле):
                нативный = последовательность()
                нативный['ожидания'][0][поле] = значение
                with self.assertRaises(ValueError): self.проверить(нативный)

    def test_дополнительная_отправка_перенос_и_другой_адрес_отклоняются(self):
        for изменение in ('добавка', 'перенос', 'адрес', 'номер'):
            with self.subTest(изменение=изменение):
                нативный = последовательность()
                if изменение == 'добавка':
                    нативный['возобновления'].append(
                        вызов('send_message_to_thread', 'ещё-H', H, 500, 9, 10))
                elif изменение == 'перенос':
                    нативный['возобновления'][0]['инструмент'] = 'handoff_thread'
                elif изменение == 'адрес':
                    нативный['возобновления'][0]['аргументы']['threadId'] = S
                else: нативный['возобновления'][0]['id'] = 'подмена'
                with self.assertRaises(ValueError): self.проверить(нативный)

    def test_последнее_адресованное_ожидание_нельзя_заменить_старым(self):
        нативный = последовательность()
        нативный['ожидания'].append(вызов('wait_threads', 'позднее-H', H, 500, 9, 10))
        with self.assertRaises(ValueError): self.проверить(нативный)

    def test_общий_ответ_перекрытие_и_неполный_префикс_отклоняются(self):
        for изменение in ('общий', 'перекрытие', 'префикс', 'схема'):
            with self.subTest(изменение=изменение):
                нативный = последовательность()
                if изменение == 'общий':
                    нативный['ожидания'][0]['аргументы']['targets'].append({'threadId': S})
                elif изменение == 'перекрытие':
                    нативный['ожидания'][1]['интервал']['начало_мс'] = 4
                elif изменение == 'префикс': нативный['источник']['начало'] = 21
                else: нативный['схема'] = 'fum.наблюдённые-вызовы-запуска.1'
                with self.assertRaises(ValueError): self.проверить(нативный)

    def test_отправки_ожидания_и_первоначальные_создания_должны_быть_закрытым_составом(self):
        for изменение in ('повтор-ожидания', 'третье-отправление', 'позднее-создание'):
            with self.subTest(изменение=изменение):
                нативный = последовательность()
                if изменение == 'повтор-ожидания': self.номера[S] = self.номера[H]
                elif изменение == 'третье-отправление': self.отправки.pop(S)
                else: нативный['вызовы'].append(вызов('create_thread', 'новое-H', H, 500, 9, 10))
                with self.assertRaises(ValueError): self.проверить(нативный)
                self.номера = {H: 'wait-H', S: 'wait-S'}
                self.отправки = {H: 'send-H', S: 'send-S'}

    def test_вторая_отправка_начинается_после_закрытия_первого_ожидания(self):
        нативный = последовательность()
        нативный['ожидания'][0]['источник'] = {'начало': 350, 'конец': 360}
        нативный['ожидания'][0]['интервал'] = {'начало_мс': 7, 'конец_мс': 8}
        нативный['ожидания'][1]['интервал'] = {'начало_мс': 9, 'конец_мс': 10}
        with self.assertRaises(ValueError): self.проверить(нативный)


if __name__ == '__main__':
    unittest.main()

"""Профиль закрытия двух задач; построение Git-фикстуры измеряется отдельно."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from фикстура_двух_до_записи import два_до_записи
import завершение_двух_до_записи


def измерить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--выход', required=True)
    аргументы = парсер.parse_args(); фазы = []
    def вызов(имя, действие):
        начало = time.perf_counter_ns(); результат = действие()
        фазы.append({'стадия': имя, 'наносекунды': time.perf_counter_ns() - начало})
        return результат
    начало = time.perf_counter_ns()
    with два_до_записи() as (_, объект, _, вход, _, _):
        фазы.append({'стадия': 'подготовка открытой Git-фикстуры', 'наносекунды': time.perf_counter_ns() - начало})
        план = вызов('предпросмотр', lambda: завершение_двух_до_записи.предпросмотр(объект, вход))
        итог = вызов('сверка под замком и запись', lambda: завершение_двух_до_записи.завершить(объект, вход, план['sha256']))
        повтор = вызов('идемпотентный повтор', lambda: завершение_двух_до_записи.завершить(объект, вход, план['sha256']))
        assert план == итог == повтор
        размер = вход['источник']['граница']
    каталог = Path(__file__).resolve().parents[1]
    пути = [каталог / 'scripts' / имя for имя in ('возобновления_до_записи.py', 'завершение_двух_до_записи.py', 'терминал_запуска.py')]
    результат = {'схема': 'fum.профиль-завершения-двух-до-записи.1', 'фазы': фазы, 'байтов_источника': размер,
        'граница': 'Открытая временная Git-фикстура; Desktop и сеть не вызываются. Совпадение checkout кода подменено. Большой реальный JSONL измеряется отдельно.',
        'исходники': {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in пути}}
    with Path(аргументы.выход).open('x') as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2); поток.write('\n')
    print(json.dumps(результат, ensure_ascii=False))


if __name__ == '__main__':
    измерить()

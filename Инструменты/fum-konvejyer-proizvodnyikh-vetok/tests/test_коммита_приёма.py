"""Конечный R сохраняет S и восстанавливается после потери ответа без повтора Git."""
import json
import os
from pathlib import Path
import subprocess
import sys
import unittest

from фикстура_приёма_интеграции import фикстура, приём, хранение


class ПроверкаКоммитаПриёма(unittest.TestCase):
    def выполнить(сам, случай):
        with фикстура() as пример:
            текст = приём.сформировать(пример['блок'])
            свидетельство = пример['отправить'](текст)
            корень = пример['корень']
            реестр = корень.parent / 'владельцы-коммита.json'
            реестр.write_bytes(хранение.байты({str(корень): {
                'задача': пример['задача'], 'ref': пример['блок']['ref']}}))
            вход = корень.parent / 'вход-коммита.json'
            вход.write_bytes(хранение.байты({'задача': пример['задача'], 'источник': str(пример['источник']),
                'план': пример['план'], 'свидетельство': свидетельство, 'текст': текст, 'реестр': str(реестр)}))
            результат = subprocess.run([sys.executable, '-B', str(Path(__file__).with_name('сценарий_коммита_приёма.py')),
                str(вход), случай], cwd=корень, env={**os.environ, 'CODEX_THREAD_ID': пример['задача']},
                capture_output=True, text=True, timeout=180)
            сам.assertEqual(0, результат.returncode, результат.stdout + результат.stderr)
            return json.loads(результат.stdout)

    def test_получатель_создаёт_слияние_с_точным_импортом(сам):
        сам.assertEqual(1, сам.выполнить('обычный')['созданий'])

    def test_потерянный_ответ_не_создаёт_второй_коммит(сам):
        сам.assertEqual(1, сам.выполнить('потерян ответ')['созданий'])

    def test_неизвестный_исход_не_повторяется(сам):
        сам.assertEqual('неизвестный исход', сам.выполнить('неизвестный исход')['отказ'])

    def test_последний_допуск_отклоняет_позднюю_подмену(сам):
        сам.assertEqual('последняя граница', сам.выполнить('последняя граница')['отказ'])

    def test_байты_импорта_не_разрешены_для_редактирования(сам):
        сам.assertIn('вне новой пары', сам.выполнить('байты импорта')['причина'])

    def test_режим_импорта_не_разрешён_для_изменения(сам):
        сам.assertIn('вне новой пары', сам.выполнить('режим импорта')['причина'])

    def test_пятый_файл_журнала_не_разрешён(сам):
        сам.assertIn('Лишний файл', сам.выполнить('лишний журнал')['причина'])


if __name__ == '__main__':
    unittest.main()

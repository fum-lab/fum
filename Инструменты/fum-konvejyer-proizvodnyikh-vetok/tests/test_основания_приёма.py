"""Происхождение назначения сохраняется после интеграции, область не расширяется."""
import unittest

from фикстура_дочернего_коммита import фикстура
import дочернее_назначение
import приём_направления as хранение


class ПроверкаОснованияПриёма(unittest.TestCase):
    def test_чтение_основания_не_разрешает_чужую_область(self):
        with фикстура() as (корень, источник, параметры):
            задача = параметры['исполнитель']
            до = дочернее_назначение.прочитать(корень, задача, источник)
            основание = дочернее_назначение.прочитать_основание(корень, задача, источник)
            self.assertEqual(дочернее_назначение.привязка(до), дочернее_назначение.привязка(основание))
            self.assertFalse(основание['разрешение_записи'])
            self.assertNotIn('снимок', основание)
            другой = корень / 'другой-слой.txt'
            другой.write_text('Принятые другим писателем данные.\n')
            хранение.гит(корень, 'add', '--all')
            хранение.гит(корень, 'commit', '-qm', 'Открытая фикстура интеграции')
            после = дочернее_назначение.прочитать_основание(корень, задача, источник)
            self.assertEqual(дочернее_назначение.привязка(основание), дочернее_назначение.привязка(после))
            self.assertFalse(после['разрешение_записи'])
            with self.assertRaisesRegex(ValueError, 'вне области'):
                дочернее_назначение.прочитать(корень, задача, источник)


if __name__ == '__main__':
    unittest.main()

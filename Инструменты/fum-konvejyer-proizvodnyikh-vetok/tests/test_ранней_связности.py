"""Незавершённый Журнал не получает готовность; поздняя порча не коммитится."""
from pathlib import Path
import unittest

from фикстура_дочернего_коммита import фикстура, коммит, НОМЕР
import test_дочернего_коммита as дочерний
from test_запуска_слоёв import хранение


class ПроверкаРаннейСвязности(unittest.TestCase):
    def подготовить(сам, корень, источник, параметры):
        return дочерний.ПроверкаДочернегоКоммита().подготовить_готовность(
            корень, источник, параметры, объявлять=False)

    def удалить_время(сам, корень, параметры):
        путь = корень / параметры['запрос']
        строки = путь.read_text().splitlines(keepends=True)
        путь.write_text(''.join(с for с in строки if 'fum-moskovskoye-vremya-rabochej-sessii' not in с))

    def проверить_нет_коммита(сам, корень, параметры):
        сам.assertEqual(параметры['исходный_коммит'], хранение.гит(корень, 'rev-parse', 'HEAD').strip())
        сам.assertFalse(Path(параметры['квитанция']).exists())

    def test_пропуск_времени_отклоняется_до_объявления_готовности(сам):
        with фикстура() as (корень, источник, параметры):
            сам.удалить_время(корень, параметры)
            файл = сам.подготовить(корень, источник, параметры)
            индекс = хранение.гит(корень, 'ls-files', '--stage')
            with сам.assertRaisesRegex(коммит.ОшибкаКоммита, 'fum-moskovskoye-vremya-rabochej-sessii'):
                коммит.объявить_готовность(файл, [НОМЕР], 600)
            сам.assertFalse(коммит.готовность.путь_этапа(параметры).exists())
            сам.assertEqual(индекс, хранение.гит(корень, 'ls-files', '--stage'))
            сам.проверить_нет_коммита(корень, параметры)

    def test_изменённое_сообщение_отклоняется_до_готовности(сам):
        with фикстура() as (корень, источник, параметры):
            файл = сам.подготовить(корень, источник, параметры)
            Path(параметры['сообщение']).write_text('Подменённое сообщение\n')
            with сам.assertRaisesRegex(коммит.ОшибкаКоммита, 'сообщение изменилось'):
                коммит.объявить_готовность(файл, [НОМЕР], 600)
            сам.assertFalse(коммит.готовность.путь_этапа(параметры).exists())
            сам.проверить_нет_коммита(корень, параметры)

    def test_поздний_пропуск_времени_не_получает_коммит(сам):
        with фикстура() as (корень, источник, параметры):
            файл = сам.подготовить(корень, источник, параметры)
            коммит.объявить_готовность(файл, [НОМЕР], 600)
            сам.удалить_время(корень, параметры)
            хранение.гит(корень, 'add', параметры['запрос'])
            with сам.assertRaises(коммит.ОшибкаКоммита):
                коммит.создать(файл, [НОМЕР])
            сам.проверить_нет_коммита(корень, параметры)


if __name__ == '__main__':
    unittest.main()

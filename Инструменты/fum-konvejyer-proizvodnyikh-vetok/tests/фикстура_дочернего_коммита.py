"""Настоящий Git и первоначальное назначение с двумя разными UUID."""
from contextlib import contextmanager
import importlib
import os
from pathlib import Path
import sys
from unittest import mock

from test_области_писателя import область_фикстура
import test_запуска_слоёв as запуск

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-svyaznostj-rabochej-sessii/scripts'))
import создание_коммита as коммит

НОМЕР = '00000000-0000-0000-0000-000000000099'


@contextmanager
def фикстура(подготовить_базу=None, подготовить_дерево=None):
    исходная = запуск.строка
    def строка(событие):
        return исходная({'timestamp': '2026-09-23T09:00:00Z', **событие})
    def база(корень):
        if подготовить_базу:
            подготовить_базу(корень)
        реестр = корень / 'Инструменты/реестр-системных-приложений-и-инструментов.md'
        реестр.parent.mkdir(parents=True, exist_ok=True)
        реестр.write_text('# Инструменты\n\nОткрытая фикстура Python и Git.\n')
    with mock.patch.object(запуск, 'строка', side_effect=строка), \
            область_фикстура(v2=True, подготовить_базу=база) as (_, _, пакет, _, назначение, дети):
        корень, задача, источник = дети['события']
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=задача), \
                mock.patch.object(коммит.готовность, 'КОРЕНЬ_СОСТОЯНИЯ', корень.parent / 'готовность'):
            if подготовить_дерево:
                подготовить_дерево(корень, задача, источник)
            журнал = importlib.import_module('журнал_слоя')
            журнал.установить(корень, задача, источник)
            читатель = importlib.import_module('дочернее_назначение')
            привязка = читатель.привязка(читатель.прочитать(корень, задача, источник))
            папка = назначение['журналы']['события']
            запрос = папка + 'запрос.md'
            путь = корень / запрос
            время = next(с for с in путь.read_text().splitlines() if с.startswith('- `fum-moskovskoye-vremya-rabochej-sessii`'))
            текст = путь.read_text().split('## Использованные инструменты', 1)[0]
            путь.write_text(текст + '## Использованные инструменты\n\n'
                '- Python 3; Git; [реестр](../../Инструменты/реестр-системных-приложений-и-инструментов.md).\n'
                + время + '\n\n'
                '## Проверки\n\nПроверить открытые байты слоя.\n\n'
                '## Повлиял на файлы\n\n- [Запрос](запрос.md).\n- [Отчёт](отчёт.md).\n'
                '- [Материалы](материалы/).\n- [События](../../Память/события/).\n')
            отчёт = путь.with_name('отчёт.md')
            заголовок = отчёт.read_text().splitlines()[0]
            отчёт.write_text(заголовок + '\n\nПроверен конечный результат слоя.\n\n'
                '## Профиль времени выполнения\n\n'
                '| Стадия | Длительность | Границы и способ измерения |\n'
                '| ------ | ------------ | ------------------------- |\n'
                '| Подготовка | не измерено | Фикстура |\n| Проверка | не измерено | Отдельный процесс |\n\n'
                'Граница профиля: открытая фикстура, без сети и реальной передачи.\n\n'
                '### Прямые запуски проверок\n\n' + коммит.отчёты.ОТКРЫТЫЙ_МАРКЕР + '\n\n'
                + коммит.отчёты.КОНЕЧНЫЙ_МАРКЕР + '\n\n'
                '## Решения и ограничения\n\nГлобальную навигацию обновляет координатор.\n\n'
                '## Источники\n\n- [Исходный запрос](запрос.md).\n')
            данные = корень / 'Память/события/данные.txt'; данные.parent.mkdir(parents=True)
            данные.write_text('проверено\n')
            параметры = {
                'схема': 'fum.создание-коммита.3', 'режим': 'дочерняя-передача',
                'корень': str(корень), 'ветка': запуск.хранение.гит(корень, 'symbolic-ref', 'HEAD').strip(),
                'исходный_коммит': пакет['постановка']['коммит'], 'родители': [пакет['постановка']['коммит']],
                'задача': запуск.ЗАДАЧА, 'исполнитель': задача, 'назначение_sha256': запуск.хранение.хэш(привязка),
                'имя_автора': 'FUM Писатель', 'запрос': запрос,
                'источник_модели': str(источник), 'кэш_модели': str(корень.parent / 'курсор-модели.json'),
                'история_модели': папка + 'материалы/история-модели.json', 'источники': [],
                'заголовок': 'Собрать события', 'описание': 'Сохранены байты конечного поручения.',
                'сообщение': str(корень.parent / 'сообщение.txt'), 'подготовка': str(корень.parent / 'подготовка.json'),
                'квитанция': str(корень.parent / 'квитанция.json'),
                'разрешённые_цели': [запрос, папка + 'отчёт.md', папка + 'материалы/история-модели.json',
                    папка + 'материалы/запуски-проверок/1_' + НОМЕР + '.json', 'Память/события/данные.txt'],
            }
            yield корень, источник, параметры

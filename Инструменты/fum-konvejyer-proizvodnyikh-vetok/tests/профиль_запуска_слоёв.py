"""Профиль конечного протокола без Desktop; подготовка Git исключена."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from test_запуска_слоёв import фикстура, исполнитель


def измерить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--выход", required=True)
    аргументы = парсер.parse_args()
    фазы = []
    def вызов(название, действие):
        начало = time.perf_counter_ns()
        результат = действие()
        фазы.append({"стадия": название, "наносекунды": time.perf_counter_ns() - начало})
        return результат
    with фикстура() as (корень, пакет, _):
        объект = исполнитель(корень)
        план = вызов("предпросмотр", lambda: объект.предпросмотр(пакет))
        вызов("сохранение плана", lambda: объект.подготовить(пакет, план["sha256"]))
        попытка = вызов("первая попытка", lambda: объект.допустить(пакет, "события"))
        повтор = вызов("повтор без внешнего вызова", lambda: исполнитель(корень).допустить(пакет, "события"))
        assert попытка["разрешён_вызов"] and not повтор["разрешён_вызов"]
        assert попытка["попытка"] == повтор["попытка"]
        размер = Path(пакет["источник"]).stat().st_size
    каталог = Path(__file__).resolve().parents[1]
    имена = [каталог / "scripts" / имя for имя in ("запуск_слоёв.py", "план_запуска_слоёв.py")]
    результат = {"схема": "fum.профиль-запуска-слоёв.1", "фазы": фазы, "байтов_источника": размер,
                 "граница": "Открытая Git-фикстура. Подготовка Git исключена; допуск происхождения исполняемого checkout подменён фикстурой. Desktop и сеть не вызываются.",
                 "исходники": {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in имена}}
    путь = Path(аргументы.выход)
    with путь.open("x") as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2)
        поток.write("\n")
    print(json.dumps(результат, ensure_ascii=False))


if __name__ == "__main__":
    измерить()

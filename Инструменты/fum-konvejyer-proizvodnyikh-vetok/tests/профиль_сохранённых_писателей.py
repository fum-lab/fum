"""Профиль конечного перехода с пакетами и синтетическим полным JSONL."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from фикстура_остановленного_поколения import остановленное_поколение, граница, строка
import завершение_сохранённых_писателей as завершение


def измерить():
    исходники = {str(п.name): х for п, х in завершение.КОД.items()}
    измерения = []
    for добавка in (0, 1048576):
        with остановленное_поколение() as (_, объект, _, _, вход, _, _):
            путь = Path(вход['источник']['путь'])
            if добавка:
                первая, остаток = путь.read_bytes().split(b'\n', 1)
                путь.write_bytes(первая + b'\n' + строка({'type': 'event_msg', 'payload': {'type': 'agent_message', 'message': 'x' * добавка}}) + остаток)
                вход['источник'] = граница(путь, корень=True)
            фазы = []
            def замер(имя, действие):
                начало = time.perf_counter_ns()
                результат = действие()
                фазы.append({'стадия': имя, 'наносекунды': time.perf_counter_ns() - начало})
                return результат
            план = замер('предпросмотр', lambda: завершение.предпросмотр(объект, вход))
            итог = замер('проверка под замком, повторная сверка и запись', lambda: завершение.завершить(объект, вход, план['sha256']))
            до = объект.хранилище.путь.read_bytes()
            повтор = замер('идемпотентный повтор', lambda: завершение.завершить(объект, вход, план['sha256']))
            if план != итог or итог != повтор or до != объект.хранилище.путь.read_bytes():
                raise AssertionError('Переход или повтор изменил результат')
            измерения.append({'байтов_источника': вход['источник']['граница'], 'фазы': фазы, 'повтор_без_изменения_байтов': True})
    if any(hashlib.sha256(п.read_bytes()).hexdigest() != х for п, х in завершение.КОД.items()):
        raise AssertionError('Код изменился во время профиля')
    return {'схема': 'fum.профиль-сохранённых-писателей.1', 'измерения': измерения, 'исходники_sha256': исходники,
            'граница': 'Открытые временные Git-деревья и синтетический JSONL. Подготовка исключена; только допуск checkout кода подменён. '
                       'Каждая фаза выполнена один раз на размер, статистической оценки разброса нет. Desktop, сеть, большой реальный JSONL и новое поколение не измерены.'}


if __name__ == '__main__':
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--выход', type=Path, required=True)
    параметры = парсер.parse_args()
    итог = измерить()
    with параметры.выход.open('x', encoding='utf-8') as поток:
        поток.write(json.dumps(итог, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(итог, ensure_ascii=False))

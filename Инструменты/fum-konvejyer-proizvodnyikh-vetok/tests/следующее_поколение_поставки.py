"""Преемник .7 включает сохранённый S, не повторяя его обработку или запуск."""
import copy
import hashlib

from фикстура_новых_веток import закрепить, хранение
from план_запуска_слоёв import сформировать_ref_ветки


def проверить(корень, объект, пакет, план, терминал):
    до = объект.хранилище.прочитать()
    S = терминал['слои']['сообщения']['S']
    хранение.гит(корень, 'merge', '--no-ff', '--no-edit', '-m', 'Объединить открытый проверенный S', S)
    ссылка = {'запуск': план['запуск'], 'терминал_sha256': терминал['sha256']}
    описание = copy.deepcopy(план['описание']); описание['предыдущий'] = ссылка
    for слой in описание['слои']:
        слой['ветка'] = сформировать_ref_ветки(слой['каталог'], 'codex')+'--g-'+терминал['sha256']
    новый = copy.deepcopy(пакет); новый['предыдущий'] = ссылка
    назначение = хранение.разобрать((корень/новый['назначение']).read_bytes())
    прежние = dict(назначение['журналы'])
    назначение['журналы'] = {с: к.replace('_12-30-00_', '_13-30-00_') for с,к in прежние.items()}
    assert all(к != прежние[с] for с,к in назначение['журналы'].items())
    сырые = хранение.байты(назначение)
    (корень/новый['назначение']).write_bytes(сырые)
    новый['постановка']['файлы'][новый['назначение']] = hashlib.sha256(сырые).hexdigest()
    закрепить(корень, новый, описание)
    C = новый['постановка']['коммит']
    хранение.гит(корень, 'merge-base', '--is-ancestor', S, C)
    просмотр = объект.предпросмотр(новый); объект.подготовить(новый, просмотр['sha256'])
    после = объект.хранилище.прочитать()
    assert после['попытки'] == до['попытки']
    assert all(после['приёмы'][ключ] == значение for ключ,значение in до['приёмы'].items())
    return {'новая_постановка': C, 'S_в_предках': True, 'прежняя_история_сохранена': True,
        'новые_внешние_попытки': 0}

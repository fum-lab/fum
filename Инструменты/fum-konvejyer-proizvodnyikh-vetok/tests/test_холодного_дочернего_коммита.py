"""Холодная передача и сохранение проверки загруженных модулей."""
from pathlib import Path
import unittest
from unittest import mock

from сценарий_холодной_передачи import выполнить
from фикстура_дочернего_коммита import фикстура, коммит, НОМЕР
import test_дочернего_коммита as тёплая_передача
from test_запуска_слоёв import хранение


class ПроверкаХолоднойПередачи(unittest.TestCase):
    def test_раздельные_процессы_создают_один_коммит_и_восстанавливают_его(self):
        результат = выполнить()
        self.assertEqual(0, результат['код'], результат['ошибка'])
        self.assertTrue(результат['повтор_совпал'])

    def test_реальная_подмена_наблюдаемых_байтов_модуля_закрывает_допуск(self):
        with фикстура() as (корень, источник, параметры):
            подготовка = тёплая_передача.ПроверкаДочернегоКоммита().подготовить_готовность(корень, источник, параметры)
            модуль = Path(коммит.передача().__file__).resolve()
            команды = коммит.команды
            прочитать = Path.read_bytes
            подменить = False
            def после_команд(*а, **к):
                nonlocal подменить
                результат = команды(*а, **к)
                подменить = True
                return результат
            def байты(путь):
                исходные = прочитать(путь)
                return исходные + '\n# Изменено\n'.encode() if подменить and путь.resolve() == модуль else исходные
            индекс = хранение.гит(корень, 'ls-files', '--stage')
            with mock.patch.object(коммит, 'команды', side_effect=после_команд), \
                    mock.patch.object(Path, 'read_bytes', байты), \
                    mock.patch.object(коммит, 'индекс', wraps=коммит.индекс) as чтение_индекса:
                with self.assertRaisesRegex(коммит.ОшибкаКоммита, 'вход ранней сверки изменился после чтения источников'):
                    коммит.создать(подготовка, [НОМЕР])
                чтение_индекса.assert_not_called()
            self.assertEqual(параметры['исходный_коммит'], хранение.гит(корень, 'rev-parse', 'HEAD').strip())
            self.assertEqual(индекс, хранение.гит(корень, 'ls-files', '--stage'))
            self.assertFalse(Path(параметры['квитанция']).exists())


if __name__ == '__main__':
    unittest.main()

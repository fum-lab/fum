"""Новый C продолжает завершённый запуск, не удаляя старые попытки."""
from contextlib import contextmanager
import copy
import importlib
import unittest

from test_завершения_запуска import пилот
from test_запуска_слоёв import хранение, ребёнок
import запуск_слоёв
import терминал_запуска


@contextmanager
def преемник(*, завершён=True):
    with пилот() as (корень, объект, пакет, старый, вход, _, _):
        модуль = importlib.import_module("завершение_запуска")
        квитанция = модуль.предпросмотр(объект, вход)
        if завершён:
            модуль.завершить(объект, вход, квитанция["sha256"])
        recovery = вход["координатор"]["HEAD"]
        хранение.гит(корень, "switch", пакет["постановка"]["ветка"].removeprefix("refs/heads/"))
        хранение.гит(корень, "merge", "--no-ff", "-m", "Включить исправленное поколение", recovery)
        новый = copy.deepcopy(пакет)
        новый.update(схема="fum.запуск-двух-слоёв.3", предыдущий={"запуск": старый["запуск"], "терминал_sha256": квитанция["sha256"]})
        новый["постановка"]["коммит"] = хранение.гит(корень, "rev-parse", "HEAD").strip()
        yield корень, объект, пакет, старый, новый, квитанция


class ПроверкаПоколенияЗапуска(unittest.TestCase):
    def test_ключи_v1_v2_не_меняются(self):
        описание = {"конвейер": "пилот", "шаг": "FUM-STEP-0233"}
        self.assertEqual(запуск_слоёв.ключ_запуска("корень", описание), хранение.хэш({
            "схема": "fum.ключ-запуска-слоёв.1", "задача": "корень", **описание}))

    def test_null_не_подменяет_явного_предшественника(self):
        with преемник() as (_, объект, _, _, новый, _):
            новый["предыдущий"] = None
            with self.assertRaises(ValueError):
                объект.предпросмотр(новый)

    def test_явный_преемник_сохраняет_историю_и_полное_поручение(self):
        with преемник() as (корень, объект, пакет, старый, новый, _):
            до = объект.хранилище.прочитать()
            план = объект.предпросмотр(новый)
            self.assertNotEqual(план["запуск"], старый["запуск"])
            self.assertEqual(план, объект.подготовить(новый, план["sha256"]))
            после = объект.хранилище.прочитать()
            self.assertEqual(до["попытки"], после["попытки"])
            self.assertEqual(до["писатели"], после["писатели"])
            self.assertEqual(до["приёмы"][старый["запуск"]], после["приёмы"][старый["запуск"]])
            допуск = объект.допустить(новый, "события")
            self.assertTrue(допуск["разрешён_вызов"])
            self.assertIn("<fum_layer_assignment>", допуск["аргументы"]["prompt"])
            self.assertIn(новый["постановка"]["коммит"], допуск["аргументы"]["prompt"])
            self.assertFalse(объект.допустить(новый, "события")["разрешён_вызов"])
            дерево, задача, источник = ребёнок(корень, новый, план["описание"]["слои"][0], допуск, 71, экранировать=True)
            наблюдение = объект.наблюдать(план["запуск"], "события", дерево, задача, источник)
            self.assertEqual(наблюдение["схема"], "fum.начальная-база-задачи.2")
            область = объект.область(план["запуск"], "события", новый["назначение"], источник)
            self.assertEqual(область["база"], новый["постановка"]["коммит"])

    def test_незавершённый_предшественник_не_заменяется(self):
        with преемник(завершён=False) as (_, объект, _, _, новый, _):
            до = объект.хранилище.путь.read_bytes()
            with self.assertRaisesRegex(ValueError, "завершён|терминал"):
                объект.предпросмотр(новый)
            self.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_терминал_и_состав_предшественника_нельзя_подменить(self):
        with преемник() as (_, объект, _, _, новый, _):
            for значение in ({"запуск": "f" * 64}, {"терминал_sha256": "f" * 64}):
                иной = copy.deepcopy(новый)
                иной["предыдущий"].update(значение)
                with self.assertRaises(ValueError):
                    объект.предпросмотр(иной)

    def test_два_C_не_создают_двух_преемников(self):
        with преемник() as (корень, объект, _, _, новый, _):
            первый = объект.предпросмотр(новый)
            объект.подготовить(новый, первый["sha256"])
            хранение.гит(корень, "commit", "--allow-empty", "-qm", "Другая версия того же преемника")
            иной = copy.deepcopy(новый)
            иной["постановка"]["коммит"] = хранение.гит(корень, "rev-parse", "HEAD").strip()
            до = объект.хранилище.путь.read_bytes()
            with self.assertRaisesRegex(ValueError, "неизменяемый"):
                объект.подготовить(иной, первый["sha256"])
            self.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_новый_C_должен_включать_recovery_из_квитанции(self):
        with преемник() as (корень, объект, пакет, _, новый, _):
            дерево = хранение.гит(корень, "rev-parse", "HEAD^{tree}").strip()
            иной_C = хранение.гит(корень, "commit-tree", дерево, "-p", пакет["постановка"]["коммит"], "-m", "Пропустить recovery").strip()
            хранение.гит(корень, "update-ref", пакет["постановка"]["ветка"], иной_C)
            новый["постановка"]["коммит"] = иной_C
            with self.assertRaises(ValueError):
                объект.предпросмотр(новый)

    def test_чужой_координатор_не_освобождает_ветки(self):
        with преемник() as (_, объект, _, старый, новый, _):
            with объект.хранилище.изменить() as состояние:
                запись = состояние["приёмы"][старый["запуск"]]
                запись["план"]["координатор"]["задача"] = "00000000-0000-4000-8000-000000000099"
            до = объект.хранилище.путь.read_bytes()
            with self.assertRaisesRegex(ValueError, "Чужая"):
                объект.предпросмотр(новый)
            self.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_посторонний_завершённый_запуск_сохраняет_резервирование(self):
        with преемник() as (_, объект, _, старый, новый, квитанция):
            with объект.хранилище.изменить() as состояние:
                # Синтетическая посторонняя история проверяет только фильтр резервирования.
                ключ = "c" * 64
                запись = copy.deepcopy(состояние["приёмы"][старый["запуск"]])
                состояние["приёмы"][ключ] = запись
                терминал = copy.deepcopy(квитанция)
                терминал["запуск"] = ключ
                терминал["sha256"] = хранение.хэш({к: в for к, в in терминал.items() if к != "sha256"})
                состояние["приёмы"][терминал_запуска.ключ(ключ)] = терминал
            до = объект.хранилище.путь.read_bytes()
            with self.assertRaisesRegex(ValueError, "другим запуском"):
                объект.предпросмотр(новый)
            self.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_цепочка_проверяет_историю_каждого_предка(self):
        with преемник() as (_, объект, _, старый, новый, квитанция):
            B = объект.предпросмотр(новый)
            объект.подготовить(новый, B["sha256"])
            with объект.хранилище.изменить() as состояние:
                # Синтетический терминал B изолирует проверку цепочки от Desktop.
                запись = состояние["приёмы"][B["запуск"]]
                попытки = {с: состояние["попытки"].get(к) for с, к in B["попытки"].items()}
                терминал = {**квитанция, "запуск": B["запуск"], "план_sha256": B["sha256"],
                    "история_sha256": хранение.хэш({"запись": запись, "попытки": попытки}),
                    "координатор": B["координатор"]}
                терминал["sha256"] = хранение.хэш({к: в for к, в in терминал.items() if к != "sha256"})
                состояние["приёмы"][терминал_запуска.ключ(B["запуск"])] = терминал
            C = copy.deepcopy(новый)
            C["предыдущий"] = {"запуск": B["запуск"], "терминал_sha256": терминал["sha256"]}
            план_C = объект.предпросмотр(C)
            self.assertNotIn(план_C["запуск"], {старый["запуск"], B["запуск"]})
            with объект.хранилище.изменить() as состояние:
                состояние["попытки"][старый["попытки"]["события"]]["ответ"]["чужая_поздняя_правка"] = True
            до = объект.хранилище.путь.read_bytes()
            with self.assertRaisesRegex(ValueError, "история предшественника"):
                объект.подготовить(C, план_C["sha256"])
            self.assertEqual(до, объект.хранилище.путь.read_bytes())


if __name__ == "__main__":
    unittest.main()

"""Порядок первоначальных передач: собственный wait и закрытый состав созданий."""
import copy
import sys
from pathlib import Path
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-reyestr-planirovaniya' / 'scripts'))
import первоначальные_ожидания_поставок as первоначальные

ПЕРВЫЙ = '11111111-1111-4111-8111-111111111111'
ВТОРОЙ = '22222222-2222-4222-8222-222222222222'


def вызов(инструмент, номер, позиция, начало, конец, ребёнок=None):
    аргументы = {'targets': [{'threadId': ребёнок}]} if инструмент == 'wait_threads' else {}
    return {'инструмент': инструмент, 'id': номер, 'аргументы': аргументы,
            'источник': {'начало': позиция, 'конец': позиция + 10},
            'интервал': {'начало_мс': начало, 'конец_мс': конец}}


def последовательность(сначала_оба=False):
    позиции = (100, 300, 200, 400) if сначала_оба else (100, 200, 300, 400)
    времена = (1, 5, 3, 7) if сначала_оба else (1, 3, 5, 7)
    создание_первого = вызов('create_thread', 'создать-первого', позиции[0], времена[0], времена[0]+1)
    ожидание_первого = вызов('wait_threads', 'ждать-первого', позиции[1], времена[1], времена[1]+1, ПЕРВЫЙ)
    создание_второго = вызов('create_thread', 'создать-второго', позиции[2], времена[2], времена[2]+1)
    ожидание_второго = вызов('wait_threads', 'ждать-второго', позиции[3], времена[3], времена[3]+1, ВТОРОЙ)
    return {'схема': 'fum.наблюдённые-вызовы-запуска.2',
            'источник': {'начало': 20}, 'начальная_граница': 20,
            'вызовы': [создание_первого, создание_второго],
            'ожидания': [ожидание_первого, ожидание_второго], 'возобновления': []}


class ПроверкаПервоначальныхОжиданийПоставок(unittest.TestCase):
    def проверить(сам, нативный):
        return первоначальные.проверить(нативный,
            {ПЕРВЫЙ: 'ждать-первого', ВТОРОЙ: 'ждать-второго'}, [ПЕРВЫЙ, ВТОРОЙ])

    def test_собственная_остановка_первого_до_создания_второго(сам):
        нативный = последовательность()
        до = copy.deepcopy(нативный)
        результат = сам.проверить(нативный)
        сам.assertEqual({ПЕРВЫЙ: 'ждать-первого', ВТОРОЙ: 'ждать-второго'},
                         {к: в['id'] for к, в in результат.items()})
        сам.assertEqual(до, нативный)

    def test_прежний_порядок_обоих_созданий_до_ожиданий(сам):
        сам.проверить(последовательность(True))

    def test_ожидание_до_собственного_создания_отклоняется(сам):
        for поле, значение in (('источник', {'начало': 90, 'конец': 99}),
                               ('интервал', {'начало_мс': 2, 'конец_мс': 4})):
            with сам.subTest(поле=поле):
                нативный = последовательность(); нативный['ожидания'][0][поле] = значение
                with сам.assertRaises(ValueError): сам.проверить(нативный)

    def test_пересечение_второго_создания_и_первого_ожидания_отклоняется(сам):
        for поле, значение in (('источник', {'начало': 205, 'конец': 215}),
                               ('интервал', {'начало_мс': 3, 'конец_мс': 5})):
            with сам.subTest(поле=поле):
                нативный = последовательность(); нативный['вызовы'][1][поле] = значение
                with сам.assertRaises(ValueError): сам.проверить(нативный)

    def test_противоречивый_порядок_двух_шкал_отклоняется(сам):
        нативный = последовательность()
        нативный['ожидания'][0]['интервал'] = {'начало_мс': 7, 'конец_мс': 8}
        нативный['ожидания'][1]['интервал'] = {'начало_мс': 9, 'конец_мс': 10}
        with сам.assertRaises(ValueError): сам.проверить(нативный)

    def test_неполный_или_лишний_состав_созданий_отклоняется(сам):
        for изменение in ('нет-второго', 'третье', 'перенос'):
            with сам.subTest(изменение=изменение):
                нативный = последовательность()
                if изменение == 'нет-второго': нативный['вызовы'].pop()
                elif изменение == 'третье': нативный['вызовы'].append(вызов('create_thread','третье',500,9,10))
                else: нативный['вызовы'][1]['инструмент'] = 'handoff_thread'
                with сам.assertRaises(ValueError): сам.проверить(нативный)

    def test_возобновление_не_является_первоначальной_передачей(сам):
        нативный = последовательность()
        нативный['возобновления'].append(вызов('send_message_to_thread','отправить',500,9,10))
        with сам.assertRaises(ValueError): сам.проверить(нативный)

    def test_общий_и_старый_ответ_не_заменяют_последний_отдельный(сам):
        for изменение in ('общий', 'поздний'):
            with сам.subTest(изменение=изменение):
                нативный = последовательность()
                if изменение == 'общий': нативный['ожидания'][0]['аргументы']['targets'].append({'threadId': ВТОРОЙ})
                else: нативный['ожидания'].append(вызов('wait_threads','поздний',500,9,10,ПЕРВЫЙ))
                with сам.assertRaises(ValueError): сам.проверить(нативный)

    def test_неполный_префикс_и_старая_схема_отклоняются(сам):
        for изменение in ('префикс', 'схема'):
            with сам.subTest(изменение=изменение):
                нативный = последовательность()
                if изменение == 'префикс': нативный['источник']['начало'] = 21
                else: нативный['схема'] = 'fum.наблюдённые-вызовы-запуска.1'
                with сам.assertRaises(ValueError): сам.проверить(нативный)

    def test_прежний_селектор_сохраняет_прежний_смысл(сам):
        import раздельные_ожидания as прежние
        with сам.assertRaisesRegex(ValueError, 'до завершения воздействия'):
            прежние.проверить(последовательность(),
                {ПЕРВЫЙ: 'ждать-первого', ВТОРОЙ: 'ждать-второго'}, [ПЕРВЫЙ, ВТОРОЙ])
        прежние.проверить(последовательность(True),
            {ПЕРВЫЙ: 'ждать-первого', ВТОРОЙ: 'ждать-второго'}, [ПЕРВЫЙ, ВТОРОЙ])

    def test_терминал_девять_выбирает_собственную_границу(сам):
        from unittest import mock
        from types import SimpleNamespace
        import завершение_отказавшего_приёма as терминал
        источник = {'путь': 'фикстура-root.jsonl', 'начало': 20, 'начало_sha256': '0'*64}
        вход = {'слои': {'события': {'задача': ПЕРВЫЙ}, 'сообщения': {'задача': ВТОРОЙ}},
                'первоначальный_источник': источник, 'источник': dict(источник),
                'первоначальные_ожидания': {ПЕРВЫЙ: 'ждать-первого', ВТОРОЙ: 'ждать-второго'}}
        попытки = {имя: {'аргументы': {}} for имя in ('события', 'сообщения')}
        нативный = последовательность()
        with mock.patch.object(терминал.прежний.нативные_вызовы,
                'прочитать_префикс', return_value=нативный):
            with mock.patch.object(первоначальные, 'проверить',
                    side_effect=LookupError('выбрана собственная граница')) as проверка:
                with сам.assertRaisesRegex(LookupError, 'выбрана собственная граница'):
                    терминал._корень(SimpleNamespace(задача='фикстура'), вход, попытки)
                проверка.assert_called_once_with(нативный, вход['первоначальные_ожидания'], [ПЕРВЫЙ, ВТОРОЙ])


if __name__ == '__main__':
    unittest.main()

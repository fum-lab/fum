"""Профиль явного преемника; подготовка Git исключена, внешних вызовов нет."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from фикстура_новых_веток import новое_поколение


def измерить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--выход", required=True)
    аргументы = парсер.parse_args()
    фазы = []
    def вызов(имя, действие):
        начало = time.perf_counter_ns()
        результат = действие()
        фазы.append({"стадия": имя, "наносекунды": time.perf_counter_ns() - начало})
        return результат
    with новое_поколение() as (_, объект, _, новый, _, _, _):
        новый.update(схема="fum.запуск-двух-слоёв.5",
                     профиль_модели={"model": "gpt-6-luna", "thinking": "low"})
        план = вызов("предпросмотр", lambda: объект.предпросмотр(новый))
        результат = вызов("сохранение преемника", lambda: объект.подготовить(новый, план["sha256"]))
        повтор = вызов("повтор подготовки", lambda: объект.подготовить(новый, план["sha256"]))
        assert план == результат == повтор
        допуск = вызов("первый допуск", lambda: объект.допустить(новый, "события"))
        повтор_допуска = вызов("повтор допуска", lambda: объект.допустить(новый, "события"))
        assert допуск["разрешён_вызов"] and not повтор_допуска["разрешён_вызов"]
    каталог = Path(__file__).resolve().parents[1]
    пути = [каталог / "scripts" / имя for имя in (
        "поколение_запуска.py", "запуск_слоёв.py", "терминал_запуска.py", "область_писателя.py",
        "завершение_запуска.py", "поручение_слоя.py", "нативное_назначение.py", "дочернее_назначение.py",
        "остановка_ребёнка.py", "сохранённый_писатель.py")]
    результат = {"схема": "fum.профиль-поколения-запуска.2",
        "профиль_модели": {"model": "gpt-6-luna", "thinking": "low"}, "фазы": фазы,
        "граница": "Открытая временная Git-фикстура. Подготовка исключена; проверка совпадения checkout кода подменена. Desktop и сеть не вызываются.",
        "исходники": {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in пути}}
    with Path(аргументы.выход).open("x") as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2)
        поток.write("\n")
    print(json.dumps(результат, ensure_ascii=False))


if __name__ == "__main__":
    измерить()

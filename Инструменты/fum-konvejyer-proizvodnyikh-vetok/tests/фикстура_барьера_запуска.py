"""Открытый запуск .7: создаётся только первый настоящий ребёнок."""
import copy
from contextlib import contextmanager
import json
from pathlib import Path

from фикстура_новых_веток import новое_поколение, закрепить
from фикстура_двух_до_записи import транспорт, первичный_вызов
from test_профиля_sol import выбрать_sol
from test_запуска_слоёв import ЗАДАЧА, строка, хранение
from test_завершения_запуска import граница
import постановка_задачи as постановка

ПОЛИТИКА = {
    'approval_policy': 'never', 'approvals_reviewer': 'user',
    'sandbox_policy': {'type': 'danger-full-access'},
    'permission_profile': {'type': 'disabled'},
    'active_permission_profile': {'id': ':danger-full-access'},
}

@contextmanager
def запуск(версия=7, *, зависимости=None, обратный_список=False):
    with новое_поколение(зависимости=зависимости) as (корень, объект, _, пакет, описание, _, _):
        if обратный_список:
            описание["слои"].reverse()
            закрепить(корень, пакет, описание)
        выбрать_sol(пакет)
        пакет['схема'] = 'fum.запуск-двух-слоёв.' + str(версия)
        план = объект.предпросмотр(пакет)
        объект.подготовить(пакет, план['sha256'])
        yield корень, объект, пакет, план


def первый(корень, объект, пакет, план, *, политика=None, сохранить=True, писатель=False):
    допуск = объект.допустить(пакет, 'события')
    задача = '00000000-0000-4000-8000-000000000001'
    ход = '00000000-0000-4000-8001-000000000001'
    база = пакет['постановка']['коммит']
    дерево = корень.parent / 'первый-ребёнок'
    хранение.гит(корень, 'worktree', 'add', '--detach', str(дерево), база)
    ответ = {'content': [{'type': 'text', 'text': json.dumps({'clientThreadId': 'ожидание-первого'})}], 'isError': False}
    if сохранить:
        объект.сохранить(план['запуск'], 'события', допуск['попытка'], ответ)
    контекст = {'cwd': str(дерево), 'model': 'gpt-6-sol', 'effort': 'ultra', **copy.deepcopy(ПОЛИТИКА if политика is None else политика)}
    записи = [
        {'type': 'session_meta', 'payload': {'id': задача, 'cwd': str(дерево), 'git': {'commit_hash': база}}},
        {'type': 'turn_context', 'payload': контекст},
        {'type': 'response_item', 'payload': {'type': 'function_call_output', 'name': 'create_thread', 'output': транспорт(допуск['аргументы']['prompt'])}},
        {'type': 'event_msg', 'payload': {'type': 'task_complete', 'turn_id': ход, 'last_agent_message': 'Запись прекращена.', 'started_at': 1, 'completed_at': 2, 'duration_ms': 1000, 'time_to_first_token_ms': 1}},
    ]
    источник = корень.parent / 'первый.jsonl'
    источник.write_bytes(b''.join(строка(з) for з in записи))
    if писатель:
        слой = next(с for с in план['описание']['слои'] if с['слой'] == 'события')
        хранение.гит(дерево, 'switch', '-c', слой['ветка'].removeprefix('refs/heads/'))
        постановка.подтвердить_начало(дерево, задача, база, источник, с_поручением=True)
        объект.наблюдать(план['запуск'], 'события', дерево, задача, источник)
    события = [
        {'type': 'session_meta', 'payload': {'id': ЗАДАЧА}},
        первичный_вызов('create_thread', 'создать-события', допуск['аргументы'], ответ, 10),
        первичный_вызов('wait_threads', 'ожидать-события', {'targets': [{'threadId': задача}]},
            {'content': [{'type': 'text', 'text': json.dumps({'polls': [{'thread': {'id': задача, 'status': {'type': 'idle'}}, 'latestTurn': {'id': ход, 'status': 'completed', 'error': None}}]})}], 'isError': False}, 20),
    ]
    return дерево, задача, источник, допуск, записи, события


def обновить(вход, события):
    путь = Path(вход['источник']['путь'])
    путь.write_bytes(b''.join(строка(с) for с in события))
    вход['источник'] = граница(путь, корень=True)
    первый = вход['слои']['события']
    первый['источник'] = граница(Path(первый['источник']['путь']))


@contextmanager
def один_до_записи(*, политика=None):
    with запуск() as (корень, объект, пакет, план):
        дерево, задача, источник, допуск, записи, события = первый(корень, объект, пакет, план, политика=политика)
        хранение.гит(корень, 'commit', '--allow-empty', '-qm', 'Открытая фикстура исправленного координатора')
        родитель = корень.parent / 'родитель-один.jsonl'; родитель.touch()
        вход = {'схема': 'fum.завершение-неудачного-запуска.6', 'запуск': план['запуск'], 'план_sha256': план['sha256'],
            'координатор': объект.хранилище._наблюдать_владельца(), 'источник': {'путь': str(родитель)}, 'ожидания': {задача: 'ожидать-события'},
            'слои': {'события': {'вид': 'остановлен-до-записи', 'попытка': допуск['попытка'], 'задача': задача, 'корень': str(дерево), 'источник': граница(источник)},
                     'сообщения': {'вид': 'не-допущен'}}, 'возобновления': {},
            'свидетельство_координатора': {'задача': ЗАДАЧА, 'единственный_координатор': True, 'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}}
        обновить(вход, события)
        yield корень, объект, пакет, план, вход, события, (дерево, задача, источник, записи)

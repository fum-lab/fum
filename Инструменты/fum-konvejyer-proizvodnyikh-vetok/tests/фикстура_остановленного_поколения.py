"""Два настоящих worktree с открытыми данными и синтетическими native событиями."""
from contextlib import contextmanager
import json

from test_области_писателя import область_фикстура
from test_завершения_запуска import граница, строка, ЗАДАЧА, хранение
from test_интервалов_нативных_вызовов import событие
import пакет_незавершённого as пакет_байтов
import хранилище_незавершённого as пакеты


def подготовить_остановку(корень, объект, запуск, план, назначение, дети):
    архивы = корень.parent / 'архивы'; архивы.mkdir(mode=0o700, exist_ok=True)
    хранилище = архивы / план['запуск']; хранилище.mkdir(mode=0o700)
    события, слои, опросы = [], {}, []
    состояние = объект.хранилище.прочитать()
    for номер, (слой, (дерево, задача, источник)) in enumerate(дети.items(), 1):
        попытка = состояние['попытки'][план['попытки'][слой]]
        ответ = {'content': [{'type': 'text', 'text': json.dumps({'threadId': задача, 'hostId': 'local'})}], 'isError': False}
        объект.сохранить(план['запуск'], слой, попытка['попытка'], ответ)
        вызов = событие('create_thread', 'создать-' + слой, попытка['аргументы'], номер * 2, номер * 2 + 1)
        вызов['payload']['item']['result'] = ответ; события.append(вызов)
        ход = '00000000-0000-4000-8000-' + str(100 + номер).zfill(12)
        with источник.open('ab') as поток:
            поток.write(строка({'type': 'event_msg', 'payload': {'type': 'task_complete', 'turn_id': ход}}))
        каталог = 'Память/' + слой + '/'
        путь = дерево / каталог / 'поток.jsonl'; путь.parent.mkdir(parents=True)
        путь.write_bytes(b'index\x00\xff\n'); хранение.гит(дерево, 'add', '--', каталог)
        путь.write_bytes(b'working\x00\xff\n')
        описание, данные = пакет_байтов.собрать(дерево, задача, запуск['постановка']['коммит'], [каталог, назначение['журналы'][слой]])
        цель = хранилище / слой; пакеты.сохранить(цель, описание, данные)
        слои[слой] = {'попытка': попытка['попытка'], 'задача': задача, 'корень': str(дерево),
                      'источник': граница(источник), 'пакет': {'путь': str(цель), 'sha256': описание['sha256']}}
        опросы.append({'thread': {'id': задача, 'status': {'type': 'idle'}},
                       'latestTurn': {'id': ход, 'status': 'completed', 'error': None}})
    уточнение = событие('send_message_to_thread', 'уточнить', {'threadId': слои['события']['задача'], 'prompt': 'Остановись'}, 7, 8)
    ожидание = событие('wait_threads', 'финальное-ожидание', {'targets': [{'threadId': с['задача']} for с in слои.values()]}, 9, 10)
    ожидание['payload']['item']['result'] = {'content': [{'type': 'text', 'text': json.dumps({'polls': опросы})}], 'isError': False}
    события += [уточнение, ожидание]
    родитель = корень.parent / ('полный-родитель-' + план['запуск'] + '.jsonl')
    родитель.write_bytes(b''.join(строка(з) for з in [{'type': 'session_meta', 'payload': {'id': ЗАДАЧА}}, *события]))
    хранение.гит(корень, 'commit', '--allow-empty', '-qm', 'Исправленный координатор')
    вход = {'схема': 'fum.завершение-неудачного-запуска.2', 'запуск': план['запуск'], 'план_sha256': план['sha256'],
        'координатор': объект.хранилище._наблюдать_владельца(), 'источник': граница(родитель, корень=True),
        'ожидание': 'финальное-ожидание', 'слои': слои,
        'свидетельство_координатора': {'задача': ЗАДАЧА, 'единственный_координатор': True,
            'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}}
    return вход, события


@contextmanager
def остановленное_поколение():
    with область_фикстура(v2=True, оба=True) as (корень, объект, запуск, план, назначение, дети):
        вход, события = подготовить_остановку(корень, объект, запуск, план, назначение, дети)
        yield корень, объект, запуск, план, вход, события, дети

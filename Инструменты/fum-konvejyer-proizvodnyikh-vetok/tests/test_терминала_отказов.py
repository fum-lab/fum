    def проверить_гонку_последнего_слоя(сам, случай, /):
        _, исполнитель, _, _, _, _, _, основания = сам.ф
        with сам.чистый_вход() as вход:
            ожидаемый = переход.предпросмотр(исполнитель, вход)
            состояние_до = исполнитель.хранилище.путь.read_bytes()
            первый = основания['события']
            if случай == 'остановка':
                путь = Path(первый.пакет['свидетельство']['остановка']['путь'])
            elif случай == 'Git':
                путь = первый.цель / 'AGENTS.md'
            elif случай == 'защищённые':
                путь = первый.цель / '.DS_Store'
                сам.assertFalse(путь.exists())
            else:
                путь = первый.вход_пакета / 'нативный/источник.jsonl'
            исходные_байты = путь.read_bytes() if путь.exists() else None
            режим = путь.stat().st_mode & 0o777 if путь.exists() else None
            прежний_приём = переход._приём
            проверок_последнего = 0
            изменён = False

            def после_проверки_последнего(*аргументы, **параметры):
                nonlocal проверок_последнего, изменён
                результат = прежний_приём(*аргументы, **параметры)
                if аргументы[2] == 'сообщения':
                    проверок_последнего += 1
                    if проверок_последнего == 2:
                        if случай == 'остановка': путь.unlink()
                        else: путь.write_bytes((исходные_байты or b'') + b'\n')
                        изменён = True
                return результат

            try:
                with patch.object(переход, '_приём', side_effect=после_проверки_последнего):
                    with сам.assertRaises((ValueError, OSError)):
                        переход.завершить(исполнитель, вход, ожидаемый['sha256'])
                сам.assertTrue(изменён)
                сам.assertEqual(2, проверок_последнего)
                сам.assertEqual(состояние_до, исполнитель.хранилище.путь.read_bytes())
            finally:
                if исходные_байты is None:
                    if путь.exists(): путь.unlink()
                else:
                    путь.write_bytes(исходные_байты)
                    путь.chmod(режим)


"""Первое сохранение квитанции не обходит строгий контракт передачи."""
import copy
import unittest

from test_перехода_координатора import переход_фикстура, хранение
from test_входа_направления import сообщение, строка
import переход_координатора
import вход_направления


class ПроверкаИзолированностиПереходов(unittest.TestCase):
    def test_многострочная_команда_сохраняется_дословно(сам):
        with переход_фикстура() as (объект, _, пакет, _, _, _):
            команда = 'Перенести координатора.\nСохранить прежнюю историю.\n'
            with open(пакет['источник'], 'ab') as поток:
                поток.write(строка(сообщение(команда, 'многострочный-ввод')))
            снимок = вход_направления.прочитать_вход(объект.корень, пакет['источник'], объект.задача)
            пакет['решение'].update(экземпляр=снимок['сообщения'][-1]['экземпляр'], контекст=снимок['контекст'],
                                   история_sha256=снимок['история_sha256'], поздние=[], актуальность='актуально')
            план = переход_координатора.предпросмотр(объект, пакет)
            сам.assertEqual(команда, план['координатор']['квитанция']['основание']['решение']['команда'])

    def test_неверный_вложенный_вход_не_становится_авторитетной_квитанцией(сам):
        with переход_фикстура() as (объект, _, пакет, _, _, _):
            план = переход_координатора.предпросмотр(объект, пакет)
            до = объект.хранилище.путь.read_bytes()
            for поле, значение in (('схема', 'неизвестная'), ('прежний_координатор', [])):
                иной = copy.deepcopy(план)
                квитанция = иной['координатор']['квитанция']
                квитанция['вход'][поле] = значение
                квитанция['sha256'] = хранение.хэш({к: в for к, в in квитанция.items() if к != 'sha256'})
                with сам.subTest(поле=поле), сам.assertRaises(ValueError):
                    with объект.хранилище.изменить() as состояние:
                        переход_координатора.установить_план(состояние, иной)
                сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_другая_задача_не_запечатывает_чужую_закрытую_цепочку(сам):
        with переход_фикстура() as (объект, _, пакет, _, _, _):
            план = переход_координатора.предпросмотр(объект, пакет)
            переход_координатора.перейти(объект, пакет, план['sha256'])
            до = объект.хранилище.путь.read_bytes()
            привязка = copy.deepcopy(план['привязка']['квитанция'])
            координатор = copy.deepcopy(план['координатор']['квитанция'])
            задача = '00000000-0000-0000-0000-000000000999'
            прежний = {'задача': задача, 'путь': пакет['прежнее_размещение']['путь'] + '-иной', 'ref': 'refs/heads/codex/иной'}
            получатель = {'задача': задача, 'путь': str(объект.корень) + '-иной', 'ref': прежний['ref'], 'HEAD': пакет['получатель']['HEAD']}
            состояние = объект.хранилище.прочитать()
            этап = copy.deepcopy(next(в for в in состояние['этапы'].values() if в['корень'] == пакет['прежнее_размещение']['путь']))
            этап.update(событие='чужой-архив', задача=задача, корень=прежний['путь'], ref=прежний['ref'])
            ключ_этапа = хранение.ключ_этапа(этап['событие'], этап['этап'])
            привязка.update(задача=задача, прежний=прежний, получатель=получатель,
                           история={'этапы': {ключ_этапа: хранение.хэш(этап)}, 'попытки': {}})
            привязка['sha256'] = хранение.хэш({к: в for к, в in привязка.items() if к != 'sha256'})
            ключ_привязки = хранение.хэш({'схема': привязка['схема'], 'прежний': прежний})
            координатор['вход'].update(задача=задача, прежнее_размещение=прежний, получатель=получатель)
            координатор['вход']['прежний_координатор']['задача'] = задача
            координатор['вход']['свидетельство_координатора']['задача'] = задача
            координатор['привязка'] = {'ключ': ключ_привязки, 'sha256': привязка['sha256']}
            координатор['sha256'] = хранение.хэш({к: в for к, в in координатор.items() if к != 'sha256'})
            ключ_координатора = хранение.хэш({'схема': координатор['схема'], 'задача': задача, 'предыдущий': пакет['предыдущий']})
            with сам.assertRaises(ValueError):
                with объект.хранилище.изменить() as состояние:
                    состояние['этапы'][ключ_этапа] = этап
                    состояние['писатели'][получатель['путь']] = {'задача': задача, 'ref': получатель['ref']}
                    состояние['приёмы'].update({ключ_привязки: привязка, ключ_координатора: координатор})
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())


if __name__ == '__main__':
    unittest.main()

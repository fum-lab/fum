"""Пути, долговечность и фактическая остановка процесса установщика J."""
import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

from test_журнала_приёма import подготовить
from фикстура_слияния_приёма import эпизод, гит, ЗАДАЧА
import журнал_приёма


class ПроверкаГраницЖурнала(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory(prefix='fum-границы-журнала-')
        сам.addCleanup(сам.временный.cleanup)
        сам.ф = подготовить(сам.временный.name)
        сам.папка = сам.ф.цель / сам.ф.блок['журнал']

    def test_индекс_или_рабочая_правка_вне_пары_не_разрешаются(сам):
        with сам.ф.приём() as приём:
            приём.применить(); исполнитель = журнал_приёма.ЖурналПриёма(приём)
            чужой = сам.ф.цель / 'второй.txt'; исходный = чужой.read_bytes()
            чужой.write_text('Не менять')
            with сам.assertRaises(ValueError): исполнитель.установить()
            сам.assertFalse(сам.папка.exists())
            гит(сам.ф.цель, 'add', 'второй.txt')
            with сам.assertRaises(ValueError): исполнитель.установить()
            сам.assertEqual(чужой.read_text(), 'Не менять')
            сам.assertFalse(сам.папка.exists())

    def test_конечные_служебные_пути_разрешены_посторонние_сохраняются_с_отказом(сам):
        with сам.ф.приём() as приём:
            приём.применить(); исполнитель = журнал_приёма.ЖурналПриёма(приём)
            первый = исполнитель.установить()
            модель = сам.папка / 'материалы/история-модели.json'
            модель.parent.mkdir(); модель.write_text('{"наблюдение": "синтетическое"}\n')
            гит(сам.ф.цель, 'add', '--', сам.ф.блок['журнал'])
            индекс = гит(сам.ф.цель, 'write-tree')
            сам.assertEqual(исполнитель.установить(), первый)
            сам.assertEqual(гит(сам.ф.цель, 'write-tree'), индекс)
            посторонний = сам.папка / 'посторонний.txt'; посторонний.write_text('Не удалять')
            with сам.assertRaises(ValueError): исполнитель.установить()
            сам.assertEqual(посторонний.read_text(), 'Не удалять')

    def test_игнорируемый_будущий_путь_отклоняется_до_намерения(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            исключения = сам.ф.папка / 'исключения'; исключения.write_text(сам.ф.блок['журнал']+'материалы/*\n')
            гит(сам.ф.цель, 'config', 'core.excludesFile', str(исключения))
            исполнитель = журнал_приёма.ЖурналПриёма(приём)
            with сам.assertRaisesRegex(ValueError, 'игнорируется'): исполнитель.установить()
            сам.assertFalse(сам.папка.exists()); сам.assertFalse(исполнитель.путь.exists())

    def test_регистр_и_ссылка_не_перенаправляют_установку(сам):
        with сам.ф.приём() as приём:
            приём.применить(); исполнитель = журнал_приёма.ЖурналПриёма(приём)
            нижний = сам.ф.цель / 'журнал'; нижний.mkdir()
            with сам.assertRaisesRegex(ValueError, 'коллизия'): исполнитель.установить()
            нижний.rmdir()
            внешний = сам.ф.папка / 'внешний'; внешний.mkdir()
            (сам.ф.цель / 'Журнал').symlink_to(внешний, target_is_directory=True)
            with сам.assertRaises(ValueError): исполнитель.установить()
            сам.assertEqual(list(внешний.iterdir()), [])

    def test_жёсткая_ссылка_и_режим_пары_отклоняются(сам):
        with сам.ф.приём() as приём:
            приём.применить(); исполнитель = журнал_приёма.ЖурналПриёма(приём)
            исполнитель.установить(); запрос = сам.папка / 'запрос.md'
            запрос.chmod(0o600)
            with сам.assertRaisesRegex(ValueError, 'режим'): исполнитель.установить()
            запрос.chmod(0o644)
            осиротевшая = сам.ф.папка / 'ссылка'; os.link(запрос, осиротевшая)
            with сам.assertRaisesRegex(ValueError, 'Жёсткая'): исполнитель.установить()
            сам.assertEqual(запрос.read_bytes(), осиротевшая.read_bytes())

    def test_отказ_синхронизации_повторно_закрепляет_совпавший_файл(сам):
        with сам.ф.приём() as приём:
            приём.применить(); исполнитель = журнал_приёма.ЖурналПриёма(приём)
            синхронизировать = эпизод.хранение.синхронизировать_каталог
            запрос = сам.папка / 'запрос.md'
            def отказ(путь):
                if путь == сам.папка and запрос.exists(): raise OSError('Не закреплён каталог')
                return синхронизировать(путь)
            with mock.patch.object(эпизод.хранение, 'синхронизировать_каталог', side_effect=отказ):
                with сам.assertRaises(OSError): исполнитель.установить()
            сам.assertEqual(исполнитель._прочитать()['состояние'], 'устанавливается')
            сам.assertEqual(stat.S_IMODE(запрос.stat().st_mode), 0o644)
            номер = запрос.stat().st_ino; наблюдения = []; синхронизация = os.fsync
            def наблюдать(дескриптор):
                наблюдения.append(os.fstat(дескриптор).st_ino)
                return синхронизация(дескриптор)
            with mock.patch.object(os, 'fsync', side_effect=наблюдать): исполнитель.установить()
            сам.assertIn(номер, наблюдения)
            сам.assertEqual(запрос.stat().st_ino, номер)
            сам.assertEqual(stat.S_IMODE(исполнитель.путь.stat().st_mode), 0o600)

    def test_обрыв_процесса_после_первого_файла_освобождает_замок(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            вход = сам.ф.папка / 'процесс.json'
            вход.write_bytes(эпизод.хранение.байты({'основание': сам.ф.основание, 'план': сам.ф.план_приёма,
                'реестр': str(сам.ф.реестр), 'эпизоды': str(сам.ф.папка / 'эпизоды')}))
            код = '''import json,os,sys
from pathlib import Path
import эпизод_приёма,слияние_приёма,журнал_приёма
журнал_приёма.ЖурналПриёма._проверить_код=lambda сам: None  # Синтетический допуск этой фикстуры.
данные=json.loads(Path(sys.argv[1]).read_bytes())
эпизод_приёма.КОРЕНЬ_СОСТОЯНИЯ=Path(данные['эпизоды'])
слияние=слияние_приёма.СлияниеПриёма(данные['основание'],данные['план'],данные['реестр'],lambda:данные['основание'])
def прервать(сам,имя):
    if имя=='запрос.md': os._exit(17)
журнал_приёма.ЖурналПриёма._граница=прервать
журнал_приёма.ЖурналПриёма(слияние).установить()
'''
            среда = {**os.environ, 'CODEX_THREAD_ID': ЗАДАЧА,
                'PYTHONPATH': str(Path(__file__).resolve().parents[1] / 'scripts')}
            результат = subprocess.run([sys.executable, '-B', '-c', код, str(вход)], cwd=сам.ф.цель,
                env=среда, capture_output=True, text=True, timeout=30)
            сам.assertEqual(результат.returncode, 17, результат.stderr)
            сам.assertTrue((сам.папка / 'запрос.md').exists())
            сам.assertFalse((сам.папка / 'отчёт.md').exists())
            сам.assertEqual(журнал_приёма.ЖурналПриёма(приём).установить()['состояние'], 'установлено')


    def test_обрыв_до_атомарной_замены_восстанавливает_свой_временный_файл(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            вход = сам.ф.папка / 'обрыв-замены.json'
            вход.write_bytes(эпизод.хранение.байты({'основание': сам.ф.основание, 'план': сам.ф.план_приёма,
                'реестр': str(сам.ф.реестр), 'эпизоды': str(сам.ф.папка / 'эпизоды')}))
            код = '''import json,os,sys
from pathlib import Path
import эпизод_приёма,слияние_приёма,журнал_приёма
журнал_приёма.ЖурналПриёма._проверить_код=lambda сам: None  # Синтетический допуск этой фикстуры.
данные=json.loads(Path(sys.argv[1]).read_bytes())
эпизод_приёма.КОРЕНЬ_СОСТОЯНИЯ=Path(данные['эпизоды'])
слияние=слияние_приёма.СлияниеПриёма(данные['основание'],данные['план'],данные['реестр'],lambda:данные['основание'])
заменить=os.replace
def прервать(откуда,куда):
    if Path(куда).name=='запрос.md': os._exit(19)
    return заменить(откуда,куда)
os.replace=прервать
журнал_приёма.ЖурналПриёма(слияние).установить()
'''
            среда = {**os.environ, 'CODEX_THREAD_ID': ЗАДАЧА,
                'PYTHONPATH': str(Path(__file__).resolve().parents[1] / 'scripts')}
            результат = subprocess.run([sys.executable, '-B', '-c', код, str(вход)], cwd=сам.ф.цель,
                env=среда, capture_output=True, text=True, timeout=30)
            сам.assertEqual(результат.returncode, 19, результат.stderr)
            сам.assertFalse((сам.папка / 'запрос.md').exists())
            сам.assertEqual(журнал_приёма.ЖурналПриёма(приём).установить()['состояние'], 'установлено')
            сам.assertEqual({п.name for п in сам.папка.iterdir()}, {'запрос.md', 'отчёт.md'})

    def test_неизвестный_временный_файл_не_присваивается_и_не_удаляется(сам):
        with сам.ф.приём() as приём:
            приём.применить(); исполнитель = журнал_приёма.ЖурналПриёма(приём)
            def остановить(точка):
                if точка == 'каталоги': raise OSError('Прервано до файлов')
            with mock.patch.object(исполнитель, '_граница', side_effect=остановить):
                with сам.assertRaises(OSError): исполнитель.установить()
            чужой = сам.папка / '.приём-чужой'; чужой.write_bytes(b'keep')
            with сам.assertRaises(ValueError): исполнитель.установить()
            сам.assertEqual(чужой.read_bytes(), b'keep')
            сам.assertFalse((сам.папка / 'запрос.md').exists())


if __name__ == '__main__':
    unittest.main()

"""Область берётся из C и наблюдения; экспорт не даёт права записи."""
from contextlib import contextmanager
import copy
import hashlib
import unittest

from test_запуска_слоёв import фикстура, подготовить, ребёнок, ЗАДАЧА, хранение

НАЗНАЧЕНИЕ = "Планирование/пилот/области.json"


@contextmanager
def область_фикстура(изменить=None, наблюдать=True, оба=False, старый_журнал=False, gitlink=False):
    with фикстура() as (корень, пакет, описание):
        назначение = {
            "схема": "fum.назначение-областей-слоёв.1", "задача": ЗАДАЧА,
            "план": пакет["план"],
            "журналы": {имя: "Журнал/2026-09-23_12-00-00_MSK_" + имя + "/"
                        for имя in ("события", "сообщения")},
        }
        if изменить:
            изменить(назначение)
        данные = хранение.байты(назначение)
        (корень / НАЗНАЧЕНИЕ).write_bytes(данные)
        (корень / "общий.txt").write_text("Общая база\n")
        if старый_журнал:
            прежний = корень / назначение["журналы"]["события"] / "запрос.md"
            прежний.parent.mkdir(parents=True)
            прежний.write_text("Прежний журнал\n")
        хранение.гит(корень, "add", ".")
        if gitlink:
            хранение.гит(корень, "update-index", "--add", "--cacheinfo", "160000," + пакет["постановка"]["коммит"] + ",чужой-модуль")
        хранение.гит(корень, "commit", "-qm", "Закрепить области")
        пакет["постановка"]["коммит"] = хранение.гит(корень, "rev-parse", "HEAD").strip()
        пакет["постановка"]["файлы"][НАЗНАЧЕНИЕ] = hashlib.sha256(данные).hexdigest()
        объект, план = подготовить(корень, пакет)
        дети = {}
        if наблюдать:
            for номер, слой in enumerate(описание["слои"], 1):
                if номер == 2 and not оба:
                    continue
                имя = слой["слой"]
                допуск = объект.допустить(пакет, имя)
                дерево, задача, источник = ребёнок(корень, пакет, слой, допуск, номер)
                объект.наблюдать(план["запуск"], имя, дерево, задача, источник)
                дети[имя] = (дерево, задача, источник)
        yield корень, объект, пакет, план, назначение, дети


def экспорт(объект, план, дети, слой="события", назначение=НАЗНАЧЕНИЕ):
    return объект.область(план["запуск"], слой, назначение, дети[слой][2])


class ПроверкаОбластиПисателя(unittest.TestCase):
    def test_два_наблюдённых_писателя_имеют_разные_области_и_uuid(self):
        with область_фикстура(оба=True) as (_, объект, пакет, план, назначение, дети):
            до = copy.deepcopy(объект.хранилище.прочитать())
            for слой, (дерево, задача, _) in дети.items():
                путь = дерево / ("Память/" + слой + "/поток.jsonl")
                путь.parent.mkdir(parents=True)
                путь.write_text('{"событие":1}\n')
                журнал = дерево / назначение["журналы"][слой]
                журнал.mkdir(parents=True)
                (журнал / "запрос.md").write_text("# Открытая фикстура\n")
                результат = экспорт(объект, план, дети, слой)
                self.assertEqual(ЗАДАЧА, результат["корневая_задача"])
                self.assertEqual(задача, результат["писатель"]["задача"])
                self.assertEqual(пакет["постановка"]["коммит"], результат["база"])
                self.assertEqual(["Память/" + слой + "/", назначение["журналы"][слой]], результат["каталоги"])
                self.assertFalse(результат["разрешение_записи"])
                self.assertEqual(результат, экспорт(объект, план, дети, слой))
            self.assertEqual(до, объект.хранилище.прочитать())

    def test_без_наблюдения_область_не_выдаётся(self):
        with область_фикстура(наблюдать=False) as (_, объект, _, план, _, _):
            with self.assertRaisesRegex(ValueError, "наблюден|наблюдён"):
                объект.область(план["запуск"], "события", НАЗНАЧЕНИЕ, "нет.jsonl")

    def test_назначение_нельзя_добавить_после_C_или_подменить_checkout(self):
        with область_фикстура() as (корень, объект, _, план, назначение, дети):
            другой = "Планирование/пилот/чужое.json"
            (корень / другой).write_bytes(хранение.байты(назначение))
            with self.assertRaisesRegex(ValueError, "манифест"):
                экспорт(объект, план, дети, назначение=другой)
            назначение["журналы"]["события"] = "Журнал/"
            (корень / НАЗНАЧЕНИЕ).write_bytes(хранение.байты(назначение))
            self.assertNotIn("Журнал/", экспорт(объект, план, дети)["каталоги"])

    def test_повтор_журнала_чужой_uuid_план_и_широкая_область_отклоняются(self):
        изменения = [
            lambda а: а["журналы"].update(события="Журнал/"),
            lambda а: а["журналы"].update(сообщения=а["журналы"]["события"]),
            lambda а: а.update(задача="00000000-0000-0000-0000-000000000099"),
            lambda а: а.update(план="Планирование/пилот/другой.json"),
            lambda а: а.update(каталоги=["/"]),
        ]
        for изменение in изменения:
            with self.subTest(изменение=изменение), область_фикстура(изменение) as (_, объект, _, план, _, дети):
                with self.assertRaises(ValueError):
                    экспорт(объект, план, дети)

    def test_чужое_изменение_видно_в_рабочем_дереве_индексе_и_коммите(self):
        for этап in ("дерево", "индекс", "коммит"):
            with self.subTest(этап=этап), область_фикстура() as (_, объект, _, план, _, дети):
                дерево = дети["события"][0]
                (дерево / "общий.txt").write_text("Чужое изменение\n")
                if этап != "дерево":
                    хранение.гит(дерево, "add", "общий.txt")
                if этап == "коммит":
                    хранение.гит(дерево, "commit", "-qm", "Чужое изменение")
                with self.assertRaisesRegex(ValueError, "вне области"):
                    экспорт(объект, план, дети)

    def test_rename_не_скрывает_исходный_чужой_путь(self):
        with область_фикстура() as (_, объект, _, план, _, дети):
            дерево = дети["события"][0]
            (дерево / "Память/события").mkdir(parents=True)
            хранение.гит(дерево, "mv", "общий.txt", "Память/события/общий.txt")
            with self.assertRaisesRegex(ValueError, "вне области"):
                экспорт(объект, план, дети)

    def test_symlink_и_регистр_не_расширяют_область(self):
        for имя in ("Память/события/ссылка", "Память/События/файл"):
            with self.subTest(имя=имя), область_фикстура() as (_, объект, _, план, _, дети):
                дерево = дети["события"][0]
                путь = дерево / имя
                путь.parent.mkdir(parents=True)
                if имя.endswith("ссылка"):
                    путь.symlink_to(дерево / "общий.txt")
                else:
                    путь.write_text("Другой регистр\n")
                with self.assertRaises(ValueError):
                    экспорт(объект, план, дети)

    def test_skip_worktree_не_скрывает_чужую_правку(self):
        with область_фикстура() as (_, объект, _, план, _, дети):
            дерево = дети["события"][0]
            хранение.гит(дерево, "update-index", "--skip-worktree", "общий.txt")
            (дерево / "общий.txt").write_text("Скрытая правка\n")
            with self.assertRaisesRegex(ValueError, "флаг"):
                экспорт(объект, план, дети)

    def test_чужой_первичный_источник_отклоняется(self):
        with область_фикстура(оба=True) as (_, объект, _, план, _, дети):
            with self.assertRaises(ValueError):
                объект.область(план["запуск"], "события", НАЗНАЧЕНИЕ, дети["сообщения"][2])

    def test_существующий_журнал_нельзя_назначить_новому_писателю(self):
        with область_фикстура(старый_журнал=True) as (_, объект, _, план, _, дети):
            with self.assertRaisesRegex(ValueError, "существует|существовал"):
                экспорт(объект, план, дети)

    def test_координатор_может_продвинуться_после_наблюдения(self):
        with область_фикстура() as (корень, объект, пакет, план, _, дети):
            (корень / "общий.txt").write_text("Поздняя работа координатора\n")
            хранение.гит(корень, "add", ".")
            хранение.гит(корень, "commit", "-qm", "Продвинуть координатора")
            self.assertEqual(пакет["постановка"]["коммит"], экспорт(объект, план, дети)["база"])

    def test_обратная_правка_в_дереве_не_скрывает_чужой_индекс(self):
        with область_фикстура() as (_, объект, _, план, _, дети):
            дерево = дети["события"][0]
            исходный = (дерево / "общий.txt").read_bytes()
            (дерево / "общий.txt").write_text("В индексе\n")
            хранение.гит(дерево, "add", ".")
            (дерево / "общий.txt").write_bytes(исходный)
            with self.assertRaisesRegex(ValueError, "вне области"):
                экспорт(объект, план, дети)


if __name__ == "__main__":
    unittest.main()

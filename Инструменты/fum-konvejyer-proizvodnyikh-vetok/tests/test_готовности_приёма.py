"""Приём не наследует старую готовность и не меняет назначенный UUID проверки."""
import json
from pathlib import Path
import tempfile
import unittest
from unittest import mock

from фикстура_дочернего_коммита import коммит


class ПроверкаГотовностиПриёма(unittest.TestCase):
    def test_привязка_поколения_и_невозможность_подмены(сам):
        with tempfile.TemporaryDirectory() as временный:
            корень = Path(временный).resolve(); проверка = '33333333-3333-4333-8333-333333333333'
            задача = '11111111-1111-4111-8111-111111111111'; папка = 'Журнал/2026-09-24_12-00-00_MSK_приём/'
            цели = [папка + x for x in ('запрос.md', 'отчёт.md', 'материалы/история-модели.json',
                'материалы/запуски-проверок/1_' + проверка + '.json')]
            параметры = {'схема': 'fum.создание-коммита.4', 'режим': 'дочерний-приём',
                'корень': str(корень), 'ветка': 'refs/heads/codex/пример', 'исходный_коммит': 'a' * 40,
                'задача': задача, 'запрос': цели[0], 'разрешённые_цели': цели,
                'исполнитель': '22222222-2222-4222-8222-222222222222', 'назначение_sha256': 'b' * 64,
                'основание_sha256': 'c' * 64, 'приём': {'основание': {'проверка': проверка}}}
            готовность = коммит.готовность
            снимок = готовность.снимок(параметры, [{'экземпляр': 'd' * 64}], [проверка], {'содержимое': 'sha256:' + 'e' * 64})
            записи = [[проверка, 'f' * 64]]
            with mock.patch.object(готовность, 'КОРЕНЬ_СОСТОЯНИЯ', корень / 'готовность'):
                первый = готовность.объявить(параметры, снимок, записи, 600)
                путь = Path(первый['путь']); исходные = путь.read_bytes()
                сам.assertEqual('fum.готовность-дочернего-приёма.1', json.loads(исходные)['схема'])
                подмена = {**параметры, 'основание_sha256': '9' * 64}
                сам.assertEqual(путь, готовность.путь_этапа(подмена))
                with сам.assertRaisesRegex(ValueError, 'привязк'): готовность.проверить_доступность(подмена)
                старая = {**параметры, 'схема': 'fum.создание-коммита.3', 'режим': 'дочерняя-передача'}
                with сам.assertRaisesRegex(ValueError, 'привязк'): готовность.проверить_доступность(старая)
                for другой, замены in (({**снимок, 'проверки': [задача]}, {проверка: задача}),
                        ({**снимок, 'разрешённые_цели': цели + ['пятый.txt']}, None)):
                    with сам.assertRaisesRegex(ValueError, 'назначенная проверка|четыре цели'):
                        готовность.объявить(параметры, другой, записи, 600, замены)
                    сам.assertEqual(исходные, путь.read_bytes())
                готовность.отозвать(параметры, 0, 'Проверить повторно')
                второй = готовность.объявить(параметры, снимок, записи, 600)
                сам.assertEqual(первый['готов_в_наносекундах_эпохи'], второй['готов_в_наносекундах_эпохи'])
                данные = json.loads(путь.read_bytes())
                данные['готовность']['поколения'][0]['снимок']['разрешённые_цели'].append('пятый.txt')
                путь.write_bytes(готовность.байты(данные))
                with сам.assertRaises(ValueError): готовность.проверить_доступность(параметры)

"""Принятый срез связан с первоначальным назначением и адресным поручением."""
import copy
import unittest

from фикстура_приёма_интеграции import фикстура, хранение, ЖУРНАЛ, прочитать_холодно
import приём_интеграции as приём


class ПроверкаПриёмаИнтеграции(unittest.TestCase):
    def прочитать(self, пример, блок=None, план=None):
        текст = приём.сформировать(блок or пример['блок'])
        свидетельство = пример['отправить'](текст)
        return приём.прочитать(пример['корень'], пример['задача'], пример['источник'],
            план or пример['план'], свидетельство, текст)

    def test_читатель_принимает_объекты_без_живого_координатора_и_не_пишет(self):
        with фикстура() as пример:
            до = хранение.гит(пример['корень'], 'status', '--porcelain')
            первый = self.прочитать(пример)
            (пример['координатор'] / 'позднее.txt').write_text('Не входит в принятый срез\n')
            хранение.гит(пример['координатор'], 'add', '.')
            хранение.гит(пример['координатор'], 'commit', '-qm', 'Продвинуть координатора')
            self.assertEqual(первый, self.прочитать(пример))
            self.assertFalse(первый['разрешение_записи'])
            self.assertEqual(пример['блок']['срез'], первый['срез'])
            self.assertEqual(пример['план']['источник']['дерево'], первый['дерево'])
            текст = приём.сформировать(пример['блок'])
            self.assertEqual(первый, прочитать_холодно(пример, текст, пример['отправить'](текст)))
            self.assertEqual(до, хранение.гит(пример['корень'], 'status', '--porcelain'))
            self.assertFalse((пример['корень'] / ЖУРНАЛ).exists())

    def test_подмена_среза_на_свидетельство_и_своего_назначения_отказывает(self):
        with фикстура() as пример:
            for замена in ({'срез': пример['блок']['источник_приёмки']},
                           {'назначение_sha256': 'f' * 64}, {'ref': 'refs/heads/codex/чужая'},
                           {'журнал': 'Журнал/'}):
                with self.subTest(замена=замена), self.assertRaises(ValueError):
                    self.прочитать(пример, {**пример['блок'], **замена})

    def test_неполученный_текст_не_считается_адресным_поручением(self):
        with фикстура() as пример:
            текст = приём.сформировать(пример['блок'])
            свидетельство = пример['отправить'](текст)
            with self.assertRaises(ValueError):
                приём.прочитать(пример['корень'], пример['задача'], пример['источник'],
                    пример['план'], свидетельство, текст + '\n')

    def test_вложенное_решение_плана_повторно_сверяется_с_Git(self):
        with фикстура() as пример:
            план = copy.deepcopy(пример['план'])
            план['источник']['решение']['граница'] = 'Подменённая граница'
            план['источник']['версия'] = хранение.хэш({'срез': план['источник']['срез'], 'решение': план['источник']['решение']})
            план['идентификатор'] = хранение.хэш({к: з for к, з in план.items() if к != 'идентификатор'})
            with self.assertRaisesRegex(ValueError, 'приёмк|приемк'):
                self.прочитать(пример, {**пример['блок'], 'план': план['идентификатор']}, план)

    def test_подмена_получателя_или_владельца_источника_отказывает(self):
        with фикстура() as пример:
            for ключ, значение in (('коммит', пример['блок']['база']), ('владелец', пример['блок']['корневая_задача']),
                                  ('дерево', 'f' * 40), ('корень', str(пример['координатор']))):
                план = copy.deepcopy(пример['план'])
                план['получатели'][0][ключ] = значение
                план['идентификатор'] = хранение.хэш({к: з for к, з in план.items() if к != 'идентификатор'})
                with self.subTest(ключ=ключ), self.assertRaisesRegex(ValueError, 'получатель'):
                    self.прочитать(пример, {**пример['блок'], 'план': план['идентификатор']}, план)
            план = copy.deepcopy(пример['план'])
            план['источник']['владелец'] = пример['задача']
            план['идентификатор'] = хранение.хэш({к: з for к, з in план.items() if к != 'идентификатор'})
            with self.assertRaisesRegex(ValueError, 'источник'):
                self.прочитать(пример, {**пример['блок'], 'план': план['идентификатор']}, план)


if __name__ == '__main__':
    unittest.main()

"""Открытый профиль первоначальной подготовки, чтения квитанции и отказа пути."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from фикстура_дочернего_коммита import фикстура
from test_окружения_писателя import подготовить_клон, ПУТЬ
import окружение_слоя


def выполнить(выход):
    фазы = []
    def замерить(имя, действие, отказ=False):
        начало = time.monotonic_ns()
        try:
            результат = действие()
        except ValueError:
            if not отказ:
                raise
            результат = None
        else:
            if отказ:
                raise AssertionError('Ожидаемый отказ не наблюдается')
        фазы.append({'стадия': имя, 'наносекунды': time.monotonic_ns() - начало,
                     'исход': 'ожидаемый отказ' if отказ else 'успех'})
        return результат
    def окружение(корень, задача, источник):
        вызов = lambda: окружение_слоя.подготовить(корень, задача, источник, ПУТЬ)
        первый = замерить('Материализация и подтверждение назначения', вызов)
        повтор = замерить('Проверка готового окружения без fetch', вызов)
        assert первый == повтор
        замерить('Отказ пути вне регистрации',
            lambda: окружение_слоя.подготовить(корень, задача, источник, '../вне'), отказ=True)
    with фикстура(подготовить_клон, окружение):
        pass
    корень = Path(__file__).resolve().parents[3]
    пути = [Path(__file__), Path(окружение_слоя.__file__), Path(окружение_слоя.зависимости.__file__),
            Path(__file__).with_name('test_окружения_писателя.py'), Path(__file__).with_name('фикстура_дочернего_коммита.py')]
    результат = {'схема': 'fum.профиль-окружения-слоя.1', 'фазы': фазы,
        'исходники': {п.relative_to(корень).as_posix(): hashlib.sha256(п.read_bytes()).hexdigest() for п in пути},
        'граница': 'Один проход открытой локальной Git-фикстуры без сети. Создание исходных репозиториев вне замеров. Проверка расположения кода подменена фикстурой. Реальный FUM, Desktop и публикация не измерены.'}
    with Path(выход).open('x') as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2); поток.write('\n')
    print(json.dumps({'фазы': фазы}, ensure_ascii=False))


if __name__ == '__main__':
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', required=True)
    выполнить(разбор.parse_args().выход)

def прочитать(дети, слой="события"):
    дерево, задача, источник = дети[слой]
    with mock.patch.dict(os.environ, {"CODEX_THREAD_ID": задача}):
        return importlib.import_module("дочернее_назначение").прочитать(дерево, задача, источник)


def заменить_поручение(источник, преобразовать):
    строки = источник.read_bytes().splitlines(keepends=True)
    запись = json.loads(строки[-1])
    начало, остаток = запись["payload"]["output"].split("  <input>", 1)
    текст, конец = остаток.rsplit("</input>", 1)
    изменённый = преобразовать(html.unescape(текст))
    запись["payload"]["output"] = начало + "  <input>" + html.escape(изменённый, quote=False) + "</input>" + конец
    источник.write_bytes(b"".join(строки[:-1]) + хранение.байты(запись))


class ПроверкаДочернегоНазначения(unittest.TestCase):
    def test_экранированный_транспорт_проходит_полное_назначение(self):
        with область_фикстура(v2=True, экранировать=True) as (_, объект, _, план, _, дети):
            дерево, задача, источник = дети["события"]
            до = источник.read_bytes()
            self.assertEqual(прочитать(дети)["слой"], "события")
            наблюдение = объект.наблюдать(план["запуск"], "события", дерево, задача, источник)
            self.assertEqual(наблюдение["задача"], задача)
            self.assertEqual(источник.read_bytes(), до)

    def test_после_начала_нельзя_сменить_закреплённое_назначение(self):
        with область_фикстура(v2=True, второе_назначение=True) as (_, _, _, _, _, дети):
            заменить_поручение(дети["события"][2], lambda т: т.replace(
                '"назначение":"Планирование/пилот/области.json"',
                '"назначение":"Планирование/пилот/другое-назначение.json"'))
            with self.assertRaisesRegex(ValueError, "Раннее подтверждение"):
                прочитать(дети)

    def test_база_проверяется_до_любого_исполняемого_контура(self):
        from test_запуска_слоёв import приём
        with область_фикстура(v2=True) as (_, _, пакет, _, _, дети):
            заменить_поручение(дети["события"][2], lambda т: т.replace(
                '"база":"' + пакет["постановка"]["коммит"] + '"', '"база":"--output=чужой-файл"'))
            with mock.patch.object(приём, "проверить_инструменты", side_effect=AssertionError("Git-контур вызван с непроверенной базой")):
                with self.assertRaisesRegex(ValueError, "коммит|OID"):
                    прочитать(дети)

    def test_план_пары_использует_назначенный_журнал_и_корневой_UUID(self):
        with область_фикстура(v2=True) as (_, _, _, _, назначение, дети):
            дерево, задача, источник = дети["события"]
            до = хранение.гит(дерево, "status", "--porcelain=v1", "--untracked-files=all")
            with mock.patch.dict(os.environ, {"CODEX_THREAD_ID": задача}):
                файлы, сведения = importlib.import_module("журнал_слоя").подготовить(дерево, задача, источник, ["Открытая команда фикстуры."])
            self.assertEqual({э.path.as_posix() for э in файлы}, {назначение["журналы"]["события"] + имя for имя in ("запрос.md", "отчёт.md")})
            текст = next(э.data.decode() for э in файлы if э.path.name == "запрос.md")
            self.assertIn("Codex-Thread-ID: " + ЗАДАЧА, текст)
            self.assertNotIn("Codex-Thread-ID: " + задача, текст)
            self.assertFalse(сведения["разрешение_установки"])
            self.assertEqual(до, хранение.гит(дерево, "status", "--porcelain=v1", "--untracked-files=all"))

    def test_первоначальная_область_не_требует_состояния_координатора(self):
        with область_фикстура(v2=True) as (корень, объект, пакет, план, назначение, дети):
            родительская = экспорт(объект, план, дети)
            гит = хранение.гит
            def собственный_гит(дерево, *а, **и):
                self.assertNotEqual(корень, дерево)
                return гит(дерево, *а, **и)
            with mock.patch.object(хранение.Хранилище, "прочитать", side_effect=AssertionError("Живое состояние родителя недоступно")), \
                    mock.patch.object(хранение, "гит", side_effect=собственный_гит):
                результат = прочитать(дети)
                self.assertEqual(результат, прочитать(дети))
            self.assertEqual(ЗАДАЧА, результат["корневая_задача"])
            self.assertEqual(дети["события"][1], результат["писатель"]["задача"])
            self.assertEqual(пакет["постановка"]["коммит"], результат["база"])
            self.assertEqual(родительская["каталоги"], результат["каталоги"])
            self.assertEqual(родительская["снимок"], результат["снимок"])
            self.assertFalse(результат["разрешение_записи"])
            self.assertIn(назначение["журналы"]["события"], результат["каталоги"])

    def test_версия_не_сбрасывает_сохранённый_запуск(self):
        with область_фикстура(наблюдать=False) as (_, объект, пакет, план, _, _):
            до = объект.хранилище.путь.read_bytes()

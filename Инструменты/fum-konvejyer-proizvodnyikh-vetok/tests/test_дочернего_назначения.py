    def test_подмены_блока_не_расширяют_полномочия(self):
        with область_фикстура(v2=True) as (_, _, _, _, _, дети):
            формат = importlib.import_module("поручение_слоя")
            источник = дети["события"][2]
            исходник = источник.read_bytes()
            изменения = [
                lambda д: д["файлы"].pop("Планирование/пилот/сообщения.md"),
                lambda д: д.update(назначение="Планирование/пилот/другое.json"),
                lambda д: д.update(слой="сообщения"),
                lambda д: д.update(корневая_задача=дети["события"][1]),
                lambda д: д.update(каталоги=["Журнал/"]),
            ]
            for изменение in изменения:
                источник.write_bytes(исходник)
                def преобразовать(текст):
                    до, остаток = текст.split(формат.НАЧАЛО)
                    данные, после = остаток.split(формат.КОНЕЦ)
                    блок = json.loads(данные)
                    изменение(блок)
                    return до + формат.НАЧАЛО + хранение.байты(блок).decode() + формат.КОНЕЦ + после
                with self.subTest(изменение=изменение):
                    заменить_поручение(источник, преобразовать)
                    with self.assertRaises(ValueError):
                        прочитать(дети)
            for замена in (lambda т: т.replace('"схема":', '"схема":"повтор", "схема":', 1),
                           lambda т: т.replace(формат.НАЧАЛО, формат.НАЧАЛО + " ", 1),
                           lambda т: т.replace(формат.НАЧАЛО, формат.НАЧАЛО * 2, 1)):
                источник.write_bytes(исходник)
                заменить_поручение(источник, замена)
                with self.assertRaises(ValueError):
                    прочитать(дети)


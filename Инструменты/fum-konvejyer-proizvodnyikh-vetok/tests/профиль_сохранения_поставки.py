"""Метки .8: подготовка, первичная сверка, запись и повтор без нового эффекта."""
import argparse
import hashlib
import json
from pathlib import Path
import statistics
import time
from unittest.mock import patch
from contextlib import ExitStack

from фикстура_сохранения_поставки import сохранение_поставки, хранение
import завершение_сохранённой_поставки as переход
import терминал_запуска
import следующее_поколение_поставки


def измерить():
    фазы = []
    def серия(имя, число, действие):
        времена, счётчики, итоги = [], [], []
        for _ in range(число):
            with patch.object(хранение, 'гит', wraps=хранение.гит) as гит:
                начало = time.perf_counter_ns(); итоги.append(действие())
                времена.append(time.perf_counter_ns()-начало); счётчики.append(гит.call_count)
        assert all(и == итоги[0] for и in итоги)
        фазы.append({'стадия': имя, 'вызовов': число, 'наносекунды': времена,
            'медиана': int(statistics.median(времена)), 'вызовы_Git': счётчики})
        return итоги[0]
    начало = time.perf_counter_ns()
    with сохранение_поставки() as (корень, объект, пакет, план, вход, _, дети):
        подготовка = time.perf_counter_ns()-начало
        до = объект.хранилище.прочитать(); сырые_до = объект.хранилище.путь.read_bytes()
        просмотр = серия('первичный предпросмотр', 3, lambda: переход.предпросмотр(объект, вход))
        assert объект.хранилище.путь.read_bytes() == сырые_до
        итог = серия('повторная сверка и запись под замком', 1,
            lambda: переход.завершить(объект, вход, просмотр['sha256']))
        assert итог == просмотр
        после = объект.хранилище.прочитать()
        assert после['приёмы'].pop(терминал_запуска.ключ(план['запуск'])) == итог and после == до
        сырые_после = объект.хранилище.путь.read_bytes()
        цели = [(переход.нативные_вызовы, 'прочитать'), (переход.поток, 'прочитать'),
            (переход.сохранённый_писатель, 'проверить'), (переход.поставка, 'проверить'),
            (переход.поставка, 'проверить_публикацию'), (переход.общие, '_координатор')]
        with ExitStack() as стек:
            запреты = [стек.enter_context(patch.object(м, и, side_effect=AssertionError('Повтор читает живое основание')))
                for м, и in цели]
            assert серия('исторический повтор', 7,
                lambda: переход.завершить(объект, вход, итог['sha256'])) == итог
            for запрет in запреты: запрет.assert_not_called()
        assert объект.хранилище.путь.read_bytes() == сырые_после
        размеры = {'Native_ROOT': вход['источник']['граница'],
            **{'Native_'+и: п.stat().st_size for и, (_, _, п) in дети.items()},
            'реестр_до': len(сырые_до), 'реестр_после': len(сырые_после)}
        преемник = серия('подготовка следующего поколения с S в предках', 1,
            lambda: следующее_поколение_поставки.проверить(корень, объект, пакет, план, итог))
    корень_кода = Path(__file__).resolve().parents[3]
    пути = set(переход.КОД) | {Path(__file__).resolve(),
        Path(__file__).with_name('фикстура_сохранения_поставки.py'),
        Path(следующее_поколение_поставки.__file__).resolve()}
    return {'схема': 'fum.профиль-сохранения-поставки.1', 'подготовка_наносекунды': подготовка,
        'фазы': фазы, 'размеры_байтов': размеры, 'преемник': преемник,
        'исходники_sha256': {str(п.relative_to(корень_кода)): hashlib.sha256(п.read_bytes()).hexdigest() for п in sorted(пути)},
        'граница': 'Реальные временные Git-деревья, штатные frozen/подготовка/квитанция и локальный bare origin; '
            'Native синтетический. Соответствие исполняемого checkout с C подменено только фикстурой. '
            'Подготовка измерена отдельно. Desktop, интернет и большой живой реестр не измерены. '
            'Повтор запрещает шесть видов живой проверки и сохраняет байты реестра.'}


if __name__ == '__main__':
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--выход', type=Path, required=True)
    аргументы = парсер.parse_args(); итог = измерить()
    with аргументы.выход.open('x', encoding='utf-8') as поток:
        json.dump(итог, поток, ensure_ascii=False, indent=2); поток.write('\n')
    print(json.dumps({'схема': итог['схема'], 'подготовка_наносекунды': итог['подготовка_наносекунды'],
        'фазы': итог['фазы']}, ensure_ascii=False))

"""Холодный процесс: настоящий нативный допуск, merge, J, v4 и итоговый R."""
import contextlib
import io
import json
from pathlib import Path
import sys
import time
from unittest import mock

корень = Path.cwd()
sys.path.insert(0, str(корень / 'Инструменты/fum-konvejyer-proizvodnyikh-vetok/scripts'))
import приём_интеграции
import эпизод_приёма as эпизод
import слияние_приёма
import журнал_приёма
import создание_коммита as коммит
import доставка_отчёта
import свежесть_слоя

данные = json.loads(Path(sys.argv[1]).read_bytes())
случай = sys.argv[2]
эпизод.КОРЕНЬ_СОСТОЯНИЯ = корень.parent / 'эпизоды-коммита-фикстуры'
коммит.готовность.КОРЕНЬ_СОСТОЯНИЯ = корень.parent / 'готовность-приёма-фикстуры'

def перечитать():
    return приём_интеграции.прочитать(корень, данные['задача'], данные['источник'],
        данные['план'], данные['свидетельство'], данные['текст'])

основание = перечитать()
исполнение = слияние_приёма.СлияниеПриёма(основание, данные['план'], данные['реестр'], перечитать)
исполнение.применить()
журнал = журнал_приёма.ЖурналПриёма(исполнение).установить()
цели = журнал['план']['будущие_пути']
запрос = корень / цели[0]
отчёт = корень / цели[1]
запрос.write_text(запрос.read_text().split('## Использованные инструменты', 1)[0]
    + '## Использованные инструменты\n\n- Python 3; Git; '
    '[реестр](../../Инструменты/реестр-системных-приложений-и-инструментов.md).\n'
    '- fum-moskovskoye-vremya-rabochej-sessii: время назначено корнем.\n\n'
    '## Проверки\n\nСохранить точный импорт и четыре файла приёма.\n\n'
    '## Повлиял на файлы\n\n- [Запрос](запрос.md).\n- [Отчёт](отчёт.md).\n'
    '- [Материалы](материалы/).\n')
отчёт.write_text(отчёт.read_text().splitlines()[0] + '\n\nПринят назначенный срез.\n\n'
    '## Профиль времени выполнения\n\n'
    '| Стадия | Длительность | Границы и способ измерения |\n'
    '| ------ | ------------ | ------------------------- |\n'
    '| Приём | не измерено | Открытая фикстура |\n'
    '| Проверка | не измерено | Настоящий отдельный процесс |\n\n'
    'Граница профиля: настоящие локальные Git и JSONL; реального Desktop нет.\n\n'
    '### Прямые запуски проверок\n\n' + коммит.отчёты.ОТКРЫТЫЙ_МАРКЕР + '\n\n'
    + коммит.отчёты.КОНЕЧНЫЙ_МАРКЕР + '\n\n'
    '## Решения и ограничения\n\nГлобальная навигация отложена до координатора.\n\n'
    '## Источники\n\n- [Исходный запрос](запрос.md).\n')
блок = основание['поручение']
путь_эпизода = эпизод.путь_эпизода(основание)
параметры = {
    'схема': 'fum.создание-коммита.4', 'режим': 'дочерний-приём',
    'корень': str(корень), 'ветка': блок['ref'], 'задача': блок['корневая_задача'],
    'исполнитель': блок['исполнитель'], 'назначение_sha256': блок['назначение_sha256'],
    'основание_sha256': основание['sha256'],
    'приём': {'основание': основание, 'план': данные['план'], 'реестр': данные['реестр'],
        'свидетельство': данные['свидетельство']},
    'исходный_коммит': блок['исходный_коммит'], 'родители': [блок['исходный_коммит'], блок['срез']],
    'имя_автора': 'FUM Писатель', 'запрос': цели[0], 'история_модели': цели[2],
    'источник_модели': данные['источник'], 'кэш_модели': str(корень.parent / 'модель-приёма.json'),
    'источники': [], 'заголовок': 'Принять интеграцию', 'описание': 'Срез доставлен без изменения импортированных байтов.',
    'сообщение': str(корень.parent / 'сообщение-приёма.txt'),
    'подготовка': str(корень.parent / 'подготовка-приёма.json'),
    'квитанция': str(путь_эпизода.with_suffix('.коммит.json')), 'разрешённые_цели': цели,
}
if случай == 'байты импорта':
    (корень / 'другой-слой.txt').write_text('подмена\n')
elif случай == 'режим импорта':
    (корень / 'другой-слой.txt').chmod(0o755)
elif случай == 'лишний журнал':
    (запрос.parent / 'пятый.txt').write_text('лишний\n')

if случай in {'байты импорта', 'режим импорта', 'лишний журнал'}:
    try:
        коммит.подготовить(параметры)
    except коммит.ОшибкаКоммита as ошибка:
        assert not (корень / цели[2]).exists()
        assert not Path(параметры['подготовка']).exists()
        assert коммит.гит(корень, 'rev-parse', 'HEAD').decode().strip() == блок['исходный_коммит']
        print(json.dumps({'отказ': случай, 'причина': str(ошибка)}, ensure_ascii=False))
        sys.exit(0)
    raise AssertionError('Импорт либо область J приняты после подмены')

коммит.подготовить(параметры)
assert json.loads(Path(параметры['подготовка']).read_bytes())['схема'] == 'fum.подготовленный-коммит.6'
время = свежесть_слоя.свежесть.format_msk(свежесть_слоя.свежесть.parse_now())
for путь in (запрос, отчёт):
    свежесть_слоя.свежесть.process_markdown_file(путь, корень, set(цели), время, False, False)
коммит.гит(корень, 'add', '--', *цели[:3])
with contextlib.redirect_stdout(io.StringIO()):
    код = коммит.отчёты.выполнить_запуск(корень, цели[0], 'Проверить доставленные байты',
        'получатель', блок['проверка'], 15,
        [sys.executable, '-c', "from pathlib import Path; assert Path('другой-слой.txt').read_text() == 'Открытый результат второго слоя\\n'"],
        класс_проверки='адресная', приёмочные_раунды=True)
    assert код == 0
    коммит.отчёты.выполнить_предпросмотр(корень, цели[0])
коммит.гит(корень, 'add', '--', *цели)
подготовка = Path(параметры['подготовка'])
коммит.объявить_готовность(подготовка, [блок['проверка']], 600)
созданий = []
гит = коммит.гит
def считать(*а, **к):
    if а[1] == 'commit': созданий.append(1)
    return гит(*а, **к)
with mock.patch.object(коммит, 'гит', side_effect=считать):
    if случай == 'последняя граница':
        сверить = коммит.готовность.сверить
        def подменить(*а, **к):
            результат = сверить(*а, **к)
            (корень / 'другой-слой.txt').write_text('Поздняя подмена\n')
            return результат
        with mock.patch.object(коммит.готовность, 'сверить', side_effect=подменить):
            try: коммит.создать(подготовка, [блок['проверка']])
            except коммит.ОшибкаКоммита: pass
            else: raise AssertionError('Поздняя подмена принята')
        assert not созданий and not Path(параметры['квитанция']).exists()
        assert гит(корень, 'rev-parse', 'HEAD').decode().strip() == блок['исходный_коммит']
        print(json.dumps({'отказ': случай}, ensure_ascii=False)); sys.exit(0)
    if случай in {'потерян ответ', 'неизвестный исход'}:
        with mock.patch.object(коммит, 'восстановить', side_effect=RuntimeError('Ответ не доставлен')):
            try: коммит.создать(подготовка, [блок['проверка']])
            except RuntimeError: pass
            else: raise AssertionError('Инъекция потери ответа не достигнута')
    if случай == 'неизвестный исход':
        файл = Path(параметры['квитанция'])
        запись = json.loads(файл.read_bytes()); запись.pop('процесс')
        коммит.сообщения._установить(файл, коммит.байты(запись))
        try: коммит.создать(подготовка, [блок['проверка']])
        except коммит.ОшибкаКоммита: pass
        else: raise AssertionError('Неизвестный исход принят')
        assert len(созданий) == 1
        print(json.dumps({'отказ': случай}, ensure_ascii=False)); sys.exit(0)
    начало = time.perf_counter_ns()
    итог = коммит.создать(подготовка, [блок['проверка']])
    первый = time.perf_counter_ns() - начало
    повторы = []
    for _ in range(3):
        начало = time.perf_counter_ns()
        assert итог == коммит.создать(подготовка, [блок['проверка']])
        повторы.append(time.perf_counter_ns() - начало)
assert len(созданий) == 1
assert итог['родители'] == параметры['родители']
assert 'gpt-6-astra; effort=low' in итог['автор']
assert коммит.гит(корень, 'log', '-1', '--format=%B').decode().rstrip().endswith('Codex-Thread-ID: ' + параметры['задача'])
исходное = доставка_отчёта.дерево(корень, блок['срез'])
результат = доставка_отчёта.дерево(корень, итог['коммит'])
assert {п: з for п, з in результат.items() if п not in цели} == исходное
assert set(результат) - set(исходное) == set(цели)
assert all(результат[п]['режим'] == '100644' for п in цели)
assert not (корень / 'приёмка.json').exists()
assert not коммит.гит(корень, 'status', '--porcelain')
квитанция = json.loads(Path(параметры['квитанция']).read_bytes())
print(json.dumps({'коммит': итог['коммит'], 'родители': итог['родители'], 'созданий': len(созданий),
    'первый_вызов_наносекунды': первый, 'повторы_наносекунды': повторы,
    'профиль_создания': квитанция['профиль']}, ensure_ascii=False))

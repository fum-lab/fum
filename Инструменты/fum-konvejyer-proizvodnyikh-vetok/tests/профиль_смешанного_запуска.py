"""Профиль стадий смешанного терминала на реальном временном Git."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from test_завершения_смешанного_запуска import смешанный_запуск, граница, строка
import завершение_смешанного_запуска as завершение


def измерить():
    измерения = []
    for добавка in (0, 1048576):
        with смешанный_запуск() as (_, объект, _, _, вход, _, _):
            путь = Path(вход['источник']['путь'])
            if добавка:
                первая, остаток = путь.read_bytes().split(b'\n', 1)
                путь.write_bytes(первая + b'\n' + строка({'type': 'event_msg',
                    'payload': {'type': 'agent_message', 'message': 'x' * добавка}}) + остаток)
                вход['источник'] = граница(путь, корень=True)
            фазы = []
            def замер(имя, действие):
                начало = time.monotonic_ns(); результат = действие()
                фазы.append({'стадия': имя, 'наносекунды': time.monotonic_ns() - начало})
                return результат
            просмотр = замер('предпросмотр', lambda: завершение.предпросмотр(объект, вход))
            итог = замер('повторная проверка и запись под замком', lambda: завершение.завершить(объект, вход, просмотр['sha256']))
            до = объект.хранилище.путь.read_bytes()
            повтор = замер('идемпотентное чтение', lambda: завершение.завершить(объект, вход, просмотр['sha256']))
            if просмотр != итог or повтор != итог or до != объект.хранилище.путь.read_bytes():
                raise AssertionError('Повтор изменил результат или реестр')
            измерения.append({'байтов_источника': вход['источник']['граница'], 'фазы': фазы})
    return {'схема': 'fum.профиль-смешанного-запуска.1', 'измерения': измерения,
        'исходники_sha256': {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in завершение.КОД},
        'граница': 'Настоящий временный Git, синтетический JSONL, подготовка исключена. Один запуск каждой стадии на размер, без оценки разброса. Desktop, сеть и большой реальный JSONL не измерены.'}


if __name__ == '__main__':
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path, required=True)
    аргументы = разбор.parse_args(); итог = измерить()
    with аргументы.выход.open('x') as файл: файл.write(json.dumps(итог, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(итог, ensure_ascii=False))

"""Обнаружение пакета не является разрешением Git-эффекта."""
import copy
import html
import os
from pathlib import Path
import unittest
from unittest import mock

from фикстура_нативного_приёма import фикстура, ЗАДАЧА, РЕБЁНОК
import приём_интеграции
import конверт_приёма as конверт

хранение = приём_интеграции.хранение


def входные(ф):
    владельцы = {str(ф['корень']): {'задача': РЕБЁНОК, 'ref': 'refs/heads/codex/child'}}
    решение = {'граница': 'Только проверка конверта; Git-объекты проверяет следующий допуск'}
    источник = {'корень': str(ф['путь'] / 'координатор'), 'ref': 'refs/heads/codex/root',
        'коммит': 'a' * 40, 'владелец': ЗАДАЧА, 'срез': 'b' * 40,
        'приёмка': {'путь': 'приёмка.json', 'sha256': 'c' * 64}, 'дерево': 'd' * 40,
        'решение': решение, 'полная_приёмка': False,
        'версия': хранение.хэш({'срез': 'b' * 40, 'решение': решение})}
    план = {'схема': 'fum.план-обратной-доставки.1', 'источник': источник,
        'владельцы_sha256': хранение.хэш(владельцы), 'получатели': [{
            'корень': str(ф['корень']), 'владелец': РЕБЁНОК, 'ref': 'refs/heads/codex/child',
            'коммит': 'e' * 40, 'дерево': 'f' * 40, 'отношение': 'недоставленные коммиты',
            'патчи': [], 'причина': 'Контрольный приём', 'зависимость': 'unknown',
            'сигнал_недоставки': True, 'подтверждение': 'unknown'}]}
    план['идентификатор'] = хранение.хэш(план)
    блок = {'схема': 'fum.поручение-дочернего-приёма.1', 'корневая_задача': ЗАДАЧА,
        'исполнитель': РЕБЁНОК, 'база': '1' * 40, 'назначение_sha256': '2' * 64,
        'слой': 'сообщения', 'корень': str(ф['корень']), 'ref': 'refs/heads/codex/child',
        'исходный_коммит': 'e' * 40, 'срез': 'b' * 40, 'источник_приёмки': 'a' * 40,
        'план': план['идентификатор'], 'журнал': 'Журнал/2026-09-24_12-00-00_MSK_принять-срез/',
        'проверка': '33333333-3333-4333-8333-333333333333'}
    текст = приём_интеграции.сформировать(блок)
    ф['send']['payload']['item']['arguments']['prompt'] = текст
    ф['транспорт']['payload']['output'] = ('<codex_delegation>\n  <source_thread_id>' + ЗАДАЧА
        + '</source_thread_id>\n  <input>' + html.escape(текст, quote=False) + '</input>\n</codex_delegation>')
    свидетельство = ф['сохранить']()
    return {'текст': текст, 'план': план, 'владельцы': владельцы, 'свидетельство': свидетельство,
        'коммит': {'имя_автора': 'FUM Писатель', 'заголовок': 'Принять срез', 'описание': 'Получен принятый срез.'}}


class ПроверкаКонверта(unittest.TestCase):
    def test_до_готовности_ожидание_не_создаёт_каталогов(сам):
        with фикстура() as ф, mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', ф['путь'] / 'частное'), \
                mock.patch.dict(os.environ, {'CODEX_THREAD_ID': РЕБЁНОК}):
            в = входные(ф)
            сам.assertIsNone(конверт.ожидать(в['текст'], 0))
            сам.assertFalse((ф['путь'] / 'частное').exists())
            сам.assertEqual([], list(ф['корень'].iterdir()))

    def test_публикация_после_send_обнаруживается_и_повтор_сохраняет_байты(сам):
        with фикстура() as ф, mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', ф['путь'] / 'частное'):
            в = входные(ф)
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ЗАДАЧА}):
                конверт.опубликовать(**в)
                путь = конверт.адрес(в['текст'])
                до = {п.name: (п.stat().st_ino, п.read_bytes()) for п in путь.iterdir()}
                конверт.опубликовать(**в)
                сам.assertEqual(до, {п.name: (п.stat().st_ino, п.read_bytes()) for п in путь.iterdir()})
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': РЕБЁНОК}):
                итог = конверт.ожидать(в['текст'], 0)
                сам.assertEqual(в, {к: итог[к] for к in в})
            сам.assertEqual([], list(ф['корень'].iterdir()))

    def test_прерванная_публикация_не_готова_и_не_перезаписывается(сам):
        with фикстура() as ф, mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', ф['путь'] / 'частное'):
            в = входные(ф)
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ЗАДАЧА}), \
                    mock.patch.object(конверт, 'установить_готовность', side_effect=OSError('Прервано')):
                with сам.assertRaises(OSError):
                    конверт.опубликовать(**в)
            путь = конверт.адрес(в['текст']); до = (путь / 'конверт.json').read_bytes()
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': РЕБЁНОК}):
                сам.assertIsNone(конверт.ожидать(в['текст'], 0))
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ЗАДАЧА}):
                with сам.assertRaisesRegex(ValueError, 'Неполная'):
                    конверт.опубликовать(**в)
            сам.assertEqual(до, (путь / 'конверт.json').read_bytes())

    def test_чужие_поля_и_неподтверждённый_send_не_публикуются(сам):
        with фикстура() as ф, mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', ф['путь'] / 'частное'), \
                mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ЗАДАЧА}):
            в = входные(ф)
            for поле in ('план', 'владельцы', 'свидетельство', 'коммит'):
                неверный = copy.deepcopy(в)
                неверный[поле]['лишнее'] = True
                with сам.subTest(поле=поле), сам.assertRaises(ValueError):
                    конверт.опубликовать(**неверный)
            неверный = copy.deepcopy(в); неверный['свидетельство']['возобновление'] = 'не-завершён'
            with сам.assertRaises(ValueError):
                конверт.опубликовать(**неверный)
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': РЕБЁНОК}), сам.assertRaises(ValueError):
                конверт.опубликовать(**в)
            сам.assertFalse((ф['путь'] / 'частное').exists())

    def test_повтор_завершает_fsync_после_установки_готовности(сам):
        with фикстура() as ф, mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', ф['путь'] / 'частное'), \
                mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ЗАДАЧА}):
            в = входные(ф); путь = конверт.адрес(в['текст'])
            настоящий = хранение.синхронизировать_каталог
            def отказ(каталог):
                if каталог == путь:
                    raise OSError('fsync после rename')
                настоящий(каталог)
            with mock.patch.object(хранение, 'синхронизировать_каталог', side_effect=отказ):
                with сам.assertRaises(OSError):
                    конверт.опубликовать(**в)
            до = {п.name: (п.stat().st_ino, п.read_bytes()) for п in путь.iterdir()}
            with mock.patch.object(хранение, 'синхронизировать_каталог', wraps=настоящий) as синхронизация:
                конверт.опубликовать(**в)
                сам.assertIn(mock.call(путь), синхронизация.call_args_list)
            сам.assertEqual(до, {п.name: (п.stat().st_ino, п.read_bytes()) for п in путь.iterdir()})

    def test_поручение_извлекается_из_нативного_входа_без_ручного_файла(сам):
        import нативное_поручение_приёма
        with фикстура() as ф, mock.patch.dict(os.environ, {'CODEX_THREAD_ID': РЕБЁНОК}):
            в = входные(ф)
            with mock.patch.object(Path, 'cwd', return_value=ф['корень']):
                сам.assertEqual(в['текст'], нативное_поручение_приёма.прочитать(ф['источник']))
                ф['сохранить'](входы=[ф['транспорт'], ф['транспорт']])
                with сам.assertRaises(ValueError):
                    нативное_поручение_приёма.прочитать(ф['источник'])

    def test_подмена_получателя_назначения_и_повторный_send_отклоняются(сам):
        with фикстура() as ф, mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', ф['путь'] / 'частное'), \
                mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ЗАДАЧА}):
            в = входные(ф)
            исходный = конверт.разобрать_текст(в['текст'])
            for поле, значение in [('назначение_sha256', '3' * 64), ('исполнитель', ЗАДАЧА), ('корень', str(ф['путь']))]:
                неверный = {**в, 'текст': приём_интеграции.сформировать({**исходный, поле: значение})}
                with сам.subTest(поле=поле), сам.assertRaises(ValueError):
                    конверт.опубликовать(**неверный)
            лишний = copy.deepcopy(ф['send']); лишний['payload']['item']['id'] = 'ещё-send'
            в['свидетельство'] = ф['сохранить']([ф['wait'], ф['send'], лишний])
            with сам.assertRaises(ValueError):
                конверт.опубликовать(**в)


if __name__ == '__main__':
    unittest.main()

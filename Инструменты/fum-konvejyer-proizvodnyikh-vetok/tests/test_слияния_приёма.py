"""Возобновляемый Git-эффект при неизменном намерении, без реального Desktop."""
import copy
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent))
from фикстура_слияния_приёма import ФикстураПриёма, гит, эпизод, КООРДИНАТОР
from доставка_план import построить_план
import слияние_приёма
import обратная_доставка


class ПроверкаСлиянияПриёма(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory(prefix='fum-приём-слияние-')
        сам.addCleanup(сам.временный.cleanup)
        сам.ф = ФикстураПриёма(сам.временный.name)

    def test_сливается_срез_а_не_свидетельство_повтор_не_читает_старую_вершину(сам):
        # Координатор может продолжить работу после выдачи неизменяемого A.
        сам.ф.записать(сам.ф.источник, 'позднее.txt', 'позднее')
        сам.ф.коммит(сам.ф.источник)
        до = сам.ф.отпечаток()[str(сам.ф.источник)]
        сам.ф.записать(сам.ф.цель, 'местное.private', 'сохранить')
        with сам.ф.приём() as приём:
            первый = приём.применить()
            сам.assertEqual(первый['стадия'], 'применено')
            сам.assertEqual(гит(сам.ф.цель, 'rev-parse', 'HEAD'), сам.ф.вершина)
            сам.assertEqual(гит(сам.ф.цель, 'rev-parse', 'MERGE_HEAD'), сам.ф.срез)
            сам.assertEqual(гит(сам.ф.цель, 'write-tree'), сам.ф.основание['дерево'])
            сам.assertFalse((сам.ф.цель / 'приёмка.json').exists())
        with сам.ф.приём(перечитать=lambda: сам.fail('Повторный первичный допуск')) as приём:
            сам.assertEqual(первый, приём.применить())
            сам.assertEqual(первый, приём.состояние())
        сам.assertEqual((сам.ф.цель / 'местное.private').read_text(), 'сохранить')
        сам.assertEqual(до, сам.ф.отпечаток()[str(сам.ф.источник)])

    def test_прерывание_после_слияния_распознаёт_эффект(сам):
        with сам.ф.приём() as приём:
            with mock.patch.object(обратная_доставка.Доставка, '_после_слияния', side_effect=OSError('Прерывание')):
                with сам.assertRaises(OSError): приём.применить()
        with сам.ф.приём(перечитать=lambda: сам.fail('Повторный допуск')) as приём:
            сам.assertEqual(приём.применить()['стадия'], 'применено')

    def test_неизвестный_эффект_не_повторяется(сам):
        выполнить = обратная_доставка.выполнить
        слияния = []
        def без_эффекта(корень, *аргументы, **параметры):
            if аргументы[0] == 'merge':
                слияния.append(аргументы)
                return subprocess.CompletedProcess(аргументы, 0, b'', b'')
            return выполнить(корень, *аргументы, **параметры)
        with сам.ф.приём() as приём, mock.patch.object(обратная_доставка, 'выполнить', side_effect=без_эффекта):
            сам.assertEqual(приём.применить()['стадия'], 'эффект не подтверждён')
            сам.assertEqual(приём.применить()['стадия'], 'эффект не подтверждён')
            сам.assertEqual(len(слияния), 1)

    def test_подмена_принятых_байтов_отклоняется(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            сам.ф.записать(сам.ф.цель, 'второй.txt', 'подмена')
            гит(сам.ф.цель, 'add', 'второй.txt')
            with сам.assertRaisesRegex(ValueError, 'Состав слияния|дерев'): приём.применить()

    def test_потеря_квитанции_не_открывает_новое_слияние(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            гит(сам.ф.цель, 'merge', '--abort')
            каталог = эпизод.путь_эпизода(сам.ф.основание).with_suffix('.доставка')
            for путь in каталог.iterdir(): путь.unlink()
            каталог.rmdir()
            with сам.assertRaisesRegex(ValueError, 'квитанц|Квитанц'): приём.применить()
            сам.assertFalse(гит(сам.ф.цель, 'status', '--porcelain'))

    def test_намерение_без_начала_доставки_не_угадывается(сам):
        with сам.ф.приём() as приём:
            эпизод.начать(сам.ф.основание, lambda: сам.ф.основание)
            with сам.assertRaisesRegex(ValueError, 'квитанц|Квитанц'): приём.применить()
        сам.assertEqual(гит(сам.ф.цель, 'rev-parse', 'HEAD'), сам.ф.вершина)

    def test_второй_журнал_того_же_эпизода_отклоняется(сам):
        with сам.ф.приём() as приём: приём.применить()
        иной = сам.ф.собрать({**сам.ф.блок, 'журнал': 'Журнал/2026-09-24_12-00-01_MSK_иной/'})
        with сам.ф.приём(основание=иной, перечитать=lambda: иной) as приём:
            with сам.assertRaisesRegex(ValueError, 'друг|измен|совпа'): приём.применить()

    def test_чужой_владелец_или_грязное_дерево_отказывает_до_намерения(сам):
        with сам.ф.приём(задача=КООРДИНАТОР) as приём:
            with сам.assertRaises(ValueError): приём.применить()
            сам.assertFalse(эпизод.КОРЕНЬ_СОСТОЯНИЯ.exists())
        сам.ф.записать(сам.ф.цель, 'работа.txt', 'чужие байты')
        with сам.ф.приём() as приём:
            with сам.assertRaises(ValueError): приём.применить()
            сам.assertIsNone(эпизод.прочитать(сам.ф.основание))

    def test_подмена_среза_на_свидетельство_не_проходит_проверку(сам):
        план = copy.deepcopy(сам.ф.план_приёма)
        план['источник']['срез'] = сам.ф.описание['коммит']
        план['идентификатор'] = эпизод.хранение.хэш({к: з for к, з in план.items() if к != 'идентификатор'})
        иной = сам.ф.собрать({**сам.ф.блок, 'срез': сам.ф.описание['коммит'], 'план': план['идентификатор']})
        with сам.assertRaises(ValueError):
            with сам.ф.приём(основание=иной, план=план, перечитать=lambda: иной) as приём: приём.применить()
        сам.assertEqual(гит(сам.ф.цель, 'rev-parse', 'HEAD'), сам.ф.вершина)

    def test_ранний_внешний_коммит_не_заменяет_допуск_нового_журнала(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            гит(сам.ф.цель, 'commit', '-m', 'Неподтверждённый коммит')
            with сам.assertRaisesRegex(ValueError, 'до подтверждённой проверки'): приём.применить()

    def test_равные_деревья_не_отменяют_назначенное_слияние_истории(сам):
        with tempfile.TemporaryDirectory() as папка:
            пример = ФикстураПриёма(папка, равное_дерево=True)
            сам.assertEqual(пример.план_приёма['получатели'][0]['отношение'], 'равное дерево')
            # Прежний маршрут по-прежнему требует смыслового решения.
            with пример.владелец(пример.план_приёма) as обычная:
                with сам.assertRaisesRegex(ValueError, 'смысловая сверка'): обычная.применить()
            with пример.приём() as приём:
                сам.assertEqual(приём.применить()['стадия'], 'применено')
            сам.assertEqual(гит(пример.цель, 'rev-parse', 'MERGE_HEAD'), пример.срез)
            сам.assertEqual(гит(пример.цель, 'write-tree'), пример.основание['дерево'])

    def test_каталог_квитанции_закреплён_до_эффекта_повтор_после_ошибки_синхронизации(сам):
        синхронизировать = эпизод.хранение.синхронизировать_каталог
        посещения = []
        with сам.ф.приём() as приём:
            каталог = эпизод.путь_эпизода(сам.ф.основание).with_suffix('.доставка')
            def отказ(путь):
                if путь == каталог.parent and каталог.exists():
                    raise OSError('Родитель каталога квитанции ещё не закреплён')
                return синхронизировать(путь)
            with mock.patch.object(эпизод.хранение, 'синхронизировать_каталог', side_effect=отказ):
                with сам.assertRaisesRegex(OSError, 'не закреплён'): приём.применить()
            сам.assertIsNone(эпизод.прочитать(сам.ф.основание))
            сам.assertFalse(гит(сам.ф.цель, 'status', '--porcelain'))
            def повтор(путь):
                if путь == каталог.parent and каталог.exists(): посещения.append(путь)
                return синхронизировать(путь)
            with mock.patch.object(эпизод.хранение, 'синхронизировать_каталог', side_effect=повтор):
                сам.assertEqual(приём.применить()['стадия'], 'применено')
            сам.assertTrue(посещения)

    def test_коллизия_входящего_пути_не_расходует_эпизод(сам):
        сам.ф.записать(сам.ф.цель, 'второй.txt', 'личные байты')
        with сам.ф.приём() as приём:
            with сам.assertRaises(ValueError): приём.применить()
            сам.assertIsNone(эпизод.прочитать(сам.ф.основание))
            (сам.ф.цель / 'второй.txt').rename(сам.ф.папка / 'сохранённые-личные-байты.txt')
            сам.assertEqual(приём.применить()['стадия'], 'применено')
        сам.assertEqual((сам.ф.папка / 'сохранённые-личные-байты.txt').read_text(), 'личные байты')

    def test_согласованный_второй_срез_не_открывает_эпизод_заново(сам):
        первый, план = copy.deepcopy(сам.ф.основание), copy.deepcopy(сам.ф.план_приёма)
        сам.ф.записать(сам.ф.источник, 'следующий.txt', 'другая принятая версия')
        сам.ф.срез = сам.ф.коммит(сам.ф.источник)
        сам.ф.описание = сам.ф.принять(сам.ф.срез)
        сам.ф.план_приёма = построить_план(сам.ф.описание, [str(сам.ф.цель)], сам.ф.владельцы)
        второй = сам.ф.собрать({**сам.ф.блок, 'срез': сам.ф.срез,
            'источник_приёмки': сам.ф.описание['коммит'], 'план': сам.ф.план_приёма['идентификатор']})
        сам.assertEqual(первый['эпизод'], второй['эпизод'])
        with сам.ф.приём(основание=первый, план=план, перечитать=lambda: первый) as приём:
            приём.применить()
        with сам.ф.приём(основание=второй, перечитать=lambda: второй) as приём:
            with сам.assertRaisesRegex(ValueError, 'друг|измен|совпа'): приём.применить()
        сам.assertEqual(гит(сам.ф.цель, 'rev-parse', 'MERGE_HEAD'), первый['срез'])


if __name__ == '__main__':
    unittest.main()

"""Преемник двух сохранённых писателей при занятых прежних refs."""
from contextlib import contextmanager
import copy
import hashlib

from фикстура_остановленного_поколения import остановленное_поколение, хранение
import завершение_сохранённых_писателей as завершение


def закрепить(корень, пакет, план):
    данные = хранение.байты(план)
    (корень / пакет['план']).write_bytes(данные)
    пакет['постановка']['файлы'][пакет['план']] = hashlib.sha256(данные).hexdigest()
    хранение.гит(корень, 'add', '--', пакет['план'], пакет['назначение'])
    хранение.гит(корень, 'commit', '-qm', 'Постановка нового поколения')
    пакет['постановка']['коммит'] = хранение.гит(корень, 'rev-parse', 'HEAD').strip()


@contextmanager
def новое_поколение():
    with остановленное_поколение() as (корень, объект, пакет, прежний, вход, _, дети):
        квитанция = завершение.предпросмотр(объект, вход)
        завершение.завершить(объект, вход, квитанция['sha256'])
        ссылка = {'запуск': прежний['запуск'], 'терминал_sha256': квитанция['sha256']}
        план = copy.deepcopy(прежний['описание'])
        план.update(схема='fum.план-запуска-двух-слоёв.2', предыдущий=ссылка)
        for слой in план['слои']:
            слой['ветка'] += '--g-' + квитанция['sha256']
        новый = copy.deepcopy(пакет)
        новый.update(схема='fum.запуск-двух-слоёв.4', предыдущий=ссылка)
        назначение = хранение.разобрать((корень / новый['назначение']).read_bytes())
        назначение['журналы'] = {с: к.replace('12-00-00', '12-30-00') for с, к in назначение['журналы'].items()}
        данные = хранение.байты(назначение)
        (корень / новый['назначение']).write_bytes(данные)
        новый['постановка']['файлы'][новый['назначение']] = hashlib.sha256(данные).hexdigest()
        закрепить(корень, новый, план)
        yield корень, объект, прежний, новый, план, квитанция, дети

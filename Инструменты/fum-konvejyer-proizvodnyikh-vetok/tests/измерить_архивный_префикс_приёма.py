"""Сравнить два независимых разбора одного архива с кешем одного плана."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import statistics
import sys
import tempfile
import time
from unittest.mock import patch

from test_запуска_слоёв import строка, ЗАДАЧА
import архивный_префикс_приёма as архивы


def измерить(описание, источник, совместный):
    исходный_читатель = архивы.нативные.прочитать
    число_разборов = время_разборов = 0

    def прочитать(*позиционные, **именованные):
        nonlocal число_разборов, время_разборов
        начало = time.monotonic_ns()
        try:
            return исходный_читатель(*позиционные, **именованные)
        finally:
            число_разборов += 1
            время_разборов += time.monotonic_ns() - начало

    начало = time.monotonic_ns()
    with patch.object(архивы.нативные, 'прочитать', side_effect=прочитать):
        первый_кеш = архивы.АрхивыПриёма(источник)
        первый = первый_кеш.прочитать(описание, ЗАДАЧА, [])
        второй_кеш = первый_кеш if совместный else архивы.АрхивыПриёма(источник)
        второй = второй_кеш.прочитать(описание, ЗАДАЧА, [])
        второй_кеш.сверить()
    длительность = time.monotonic_ns() - начало
    assert первый == второй
    assert число_разборов == (1 if совместный else 2)
    нормализованный = copy.deepcopy(первый)
    нормализованный['источник']['путь'] = '<неизменяемый-архив>'
    return {
        'режим': 'кеш-одного-плана' if совместный else 'независимый-разбор-для-каждого-потребителя',
        'всего_наносекунды': длительность,
        'разбор_наносекунды': время_разборов,
        'разборов': число_разборов,
        'попаданий': второй_кеш.попадания,
        'результат_sha256': hashlib.sha256(архивы.хранение.байты(нормализованный)).hexdigest(),
    }


def выполнить():
    параметры = argparse.ArgumentParser(description=__doc__)
    параметры.add_argument('--выход', type=Path, required=True)
    параметры.add_argument('--строк', type=int, default=10000)
    параметры.add_argument('--повторов', type=int, default=3)
    аргументы = параметры.parse_args()
    if not 1 <= аргументы.строк <= 100000 or not 3 <= аргументы.повторов <= 20:
        параметры.error('Нужны 1–100000 строк и 3–20 измеряемых повторов')
    if аргументы.выход.exists() or аргументы.выход.is_symlink():
        параметры.error('Выход должен быть новым обычным файлом')
    начало_профиля = time.monotonic_ns()
    with tempfile.TemporaryDirectory(prefix='fum-профиль-архива-') as временное:
        каталог = Path(временное).resolve()
        начало = строка({'type': 'session_meta', 'payload': {'id': ЗАДАЧА}})
        событие = строка({'type': 'event_msg', 'payload': {'type': 'token_count'}})
        префикс = начало + событие * аргументы.строк
        архив, полный = каталог / 'архив.jsonl', каталог / 'полный.jsonl'
        архив.write_bytes(префикс); полный.write_bytes(префикс + событие)
        архив.chmod(0o400); полный.chmod(0o400)
        описание = {'путь': str(архив), 'начало': len(начало),
            'начало_sha256': hashlib.sha256(начало).hexdigest(),
            'граница': len(префикс), 'sha256': hashlib.sha256(префикс).hexdigest()}
        источник = dict(описание, путь=str(полный), граница=полный.stat().st_size,
            sha256=hashlib.sha256(полный.read_bytes()).hexdigest())
        прогрев = [измерить(описание, источник, режим) for режим in (False, True)]
        повторы = []
        for номер in range(аргументы.повторов):
            for режим in ((False, True) if номер % 2 == 0 else (True, False)):
                повторы.append(dict(измерить(описание, источник, режим), повтор=номер + 1))
        assert len({п['результат_sha256'] for п in прогрев + повторы}) == 1
        итог = {
            'схема': 'fum.профиль-архивного-префикса.1',
            'граница': 'Компонент физического архива: два потребителя и заключительная сверка; без Git, Desktop и полного терминала',
            'нормализация': 'Только путь временного архива в хэше результата заменён постоянной меткой; до нормализации результаты потребителей равны',
            'python': sys.version,
            'строк': аргументы.строк,
            'вход': {'архив_байты': len(префикс), 'архив_sha256': описание['sha256'],
                'полный_байты': источник['граница'], 'полный_sha256': источник['sha256']},
            'сценарий_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'исполнитель_sha256': hashlib.sha256(Path(архивы.__file__).read_bytes()).hexdigest(),
            'читатель_sha256': hashlib.sha256(Path(архивы.нативные.__file__).read_bytes()).hexdigest(),
            'прогрев': прогрев, 'повторы': повторы,
            'медианы_наносекунды': {
                имя: int(statistics.median(п['всего_наносекунды'] for п in повторы if п['режим'] == имя))
                for имя in {п['режим'] for п in повторы}},
            'весь_профиль_наносекунды': time.monotonic_ns() - начало_профиля,
        }
    аргументы.выход.parent.mkdir(parents=True, exist_ok=True)
    with аргументы.выход.open('x', encoding='utf-8') as запись:
        json.dump(итог, запись, ensure_ascii=False, indent=2); запись.write('\n')
    print(json.dumps({'профиль': str(аргументы.выход),
        'медианы_наносекунды': итог['медианы_наносекунды'],
        'результат_sha256': повторы[0]['результат_sha256']}, ensure_ascii=False))


if __name__ == '__main__': выполнить()

"""Профиль селектора первоначальных ожиданий; Git, JSONL и Desktop исключены."""
import argparse
import hashlib
import json
import platform
from pathlib import Path
import resource
import statistics
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-reyestr-planirovaniya' / 'scripts'))
import первоначальные_ожидания_поставок as текущие
import раздельные_ожидания as прежние
from test_первоначальных_ожиданий_поставок import последовательность, ПЕРВЫЙ, ВТОРОЙ


def измерить(модуль, вход, номера, дети, повторов):
    начало = time.monotonic_ns()
    for _ in range(повторов): модуль.проверить(вход, номера, дети)
    return time.monotonic_ns() - начало


def главная():
    разбор = argparse.ArgumentParser()
    разбор.add_argument('--выход', required=True)
    параметры = разбор.parse_args()
    номера = {ПЕРВЫЙ: 'ждать-первого', ВТОРОЙ: 'ждать-второго'}
    дети = [ПЕРВЫЙ, ВТОРОЙ]; общий = последовательность(True); собственный = последовательность()
    ожидаемый = прежние.проверить(общий, номера, дети)
    assert текущие.проверить(общий, номера, дети) == ожидаемый
    assert {к: в['id'] for к, в in текущие.проверить(собственный, номера, дети).items()} == номера
    for модуль in (прежние, текущие): измерить(модуль, общий, номера, дети, 20)
    измерить(текущие, собственный, номера, дети, 20)
    замеры = []
    for номер in range(7):
        порядок = [('прежний', прежние), ('текущий', текущие)]
        if номер % 2: порядок.reverse()
        длительности = {имя: измерить(модуль, общий, номера, дети, 1000) for имя, модуль in порядок}
        длительности['собственная_остановка'] = измерить(текущие, собственный, номера, дети, 1000)
        замеры.append({'порядок': [имя for имя, _ in порядок], 'длительности_нс': длительности})
    медианы = {имя: int(statistics.median(з['длительности_нс'][имя] for з in замеры))
               for имя in ('прежний', 'текущий', 'собственная_остановка')}
    входные_байты = (json.dumps({'общий': общий, 'собственный': собственный, 'номера': номера, 'дети': дети},
                        ensure_ascii=False, sort_keys=True, separators=(',', ':'))+'\n').encode()
    результат = {'схема': 'fum.профиль-первоначальных-ожиданий.1',
        'python': platform.python_version(), 'платформа': platform.platform(),
        'вход_sha256': hashlib.sha256(входные_байты).hexdigest(),
        'модули': {Path(м.__file__).name: hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
                   for м in (прежние, текущие)},
        'прогрев_вызовов': 20, 'вызовов_в_пакете': 1000, 'замеры': замеры,
        'медианы_пакетов_нс': медианы, 'rss_максимум_процесса': int(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss),
        'rss_единица': 'байты' if sys.platform == 'darwin' else 'КиБ',
        'граница': 'Чистый селектор и неизменные разобранные открытые входы; импорт, Git, JSONL и Desktop исключены. RSS относится ко всему процессу.',
        'решение': 'Дополнительные проверки закрытого состава и двух шкал необходимы. Профиль фиксирует стоимость, не доказывает ускорения полного терминала; оптимизация селектора отдельно не требуется.'}
    with Path(параметры.выход).open('x', encoding='utf-8') as поток:
        json.dump(результат, поток, ensure_ascii=False, sort_keys=True); поток.write('\n')
    print(json.dumps({'медианы_пакетов_нс': медианы, 'решение': результат['решение']}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

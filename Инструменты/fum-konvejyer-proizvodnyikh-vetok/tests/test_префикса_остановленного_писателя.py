"""Прежний остановленный ход читается из выросшего Native без подмены пути."""
import unittest

from фикстура_сохранения_поставки import сохранение_поставки
import поток_остановленного_писателя as поток
from test_запуска_слоёв import строка


class ПроверкаПрежнегоПрефикса(unittest.TestCase):
    def test_новый_хвост_не_заменяет_прежнюю_конечную_остановку(сам):
        with сохранение_поставки() as (_, объект, пакет, план, вход, _, дети):
            слой_сообщений = вход['слои']['сообщения']; путь = дети['сообщения'][2]
            прежние = путь.read_bytes()
            ожидание = вход['ожидания'][слой_сообщений['задача']]
            import нативные_вызовы
            нативный = нативные_вызовы.прочитать(вход['источник'], объект.задача,
                ожидания=[слой_сообщений['задача']], интервалы=True)
            выбранное_ожидание = next(запись_ожидания for запись_ожидания in нативный['ожидания'] if запись_ожидания['id'] == ожидание)
            попытка = объект.хранилище.прочитать()['попытки'][план['попытки']['сообщения']]
            аргументы_чтения = (слой_сообщений['источник'], слой_сообщений['задача'], слой_сообщений['корень'], пакет['постановка']['коммит'],
                попытка['аргументы']['model'], попытка['аргументы']['thinking'], выбранное_ожидание)
            хвост = строка({'type':'event_msg','payload':{'type':'task_complete',
                'turn_id':'99999999-9999-4999-8999-999999999999'}})
            путь.write_bytes(прежние + хвост)
            with сам.assertRaisesRegex(ValueError, 'полный источник'):
                поток.прочитать(*аргументы_чтения)
            полные, идентичность, ход = поток.прочитать_префикс(*аргументы_чтения)
            сам.assertEqual(прежние + хвост, полные)
            сам.assertEqual(2, len(идентичность))
            сам.assertNotEqual('99999999-9999-4999-8999-999999999999', ход)
            другой = dict(слой_сообщений['источник'], граница=True)
            with сам.assertRaises(ValueError): поток.прочитать_префикс(другой, *аргументы_чтения[1:])
            другой = dict(слой_сообщений['источник'], sha256='0'*64)
            with сам.assertRaises(ValueError): поток.прочитать_префикс(другой, *аргументы_чтения[1:])


if __name__ == '__main__': unittest.main()

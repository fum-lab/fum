"""Новый Журнал получателя: точная установка и сохранение последующего заполнения."""
import copy
import os
from pathlib import Path
import stat
import tempfile
import unittest
from unittest import mock

from фикстура_слияния_приёма import ФикстураПриёма, эпизод, гит, ЗАДАЧА, КООРДИНАТОР
import приём_интеграции
import журнал_приёма


def подготовить(папка):
    пример = ФикстураПриёма(папка)
    основание = copy.deepcopy(пример.основание)
    # Это явно синтетический допуск с каноническим текстом, не настоящий Desktop.
    основание['нативный_приём'] = {'схема': 'fum.нативный-приём.1',
        'текст': приём_интеграции.сформировать(пример.блок),
        'корневая_задача': КООРДИНАТОР, 'исполнитель': ЗАДАЧА}
    основание['sha256'] = эпизод.хранение.хэш({к: з for к, з in основание.items() if к != 'sha256'})
    пример.основание = основание
    return пример


class ПроверкаЖурналаПриёма(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory(prefix='fum-журнал-приёма-')
        сам.addCleanup(сам.временный.cleanup)
        сам.ф = подготовить(сам.временный.name)
        сам.папка = сам.ф.цель / сам.ф.блок['журнал']

    def test_пара_содержит_поручение_и_корневой_идентификатор(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            до = гит(сам.ф.цель, 'write-tree')
            результат = журнал_приёма.ЖурналПриёма(приём).установить()
            сам.assertEqual(результат['состояние'], 'установлено')
            сам.assertEqual(гит(сам.ф.цель, 'write-tree'), до)
            сам.assertEqual(гит(сам.ф.цель, 'rev-parse', 'HEAD'), сам.ф.вершина)
            текст = (сам.папка / 'запрос.md').read_text()
            сам.assertIn(сам.ф.основание['нативный_приём']['текст'], текст)
            сам.assertIn('Codex-Thread-ID: ' + КООРДИНАТОР, текст)
            инструменты = текст.split('## Использованные инструменты', 1)[1].split('## Проверки', 1)[0]
            сам.assertIn('отдельного поручения приёма', инструменты)
            сам.assertIn(сам.ф.блок['план'], инструменты)
            сам.assertIn('без получения нового времени', инструменты)
            for имя in ['запрос.md', 'отчёт.md']:
                сам.assertEqual(stat.S_IMODE((сам.папка / имя).stat().st_mode), 0o644)
            сам.assertFalse((сам.ф.цель / 'Журнал/README.md').exists())

    def test_нет_подтверждённого_слияния_или_чужой_владелец(сам):
        with сам.ф.приём() as приём:
            with сам.assertRaises(ValueError): журнал_приёма.ЖурналПриёма(приём).установить()
            сам.assertFalse(сам.папка.exists())
            приём.применить()
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': КООРДИНАТОР}):
                with сам.assertRaises(ValueError): журнал_приёма.ЖурналПриёма(приём).установить()
            сам.assertFalse(сам.папка.exists())

    def test_обрыв_после_первого_файла_восстанавливается_из_намерения(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            исполнитель = журнал_приёма.ЖурналПриёма(приём)
            def остановить(точка):
                if точка == 'запрос.md': raise OSError('Прервано')
            with mock.patch.object(исполнитель, '_граница', side_effect=остановить):
                with сам.assertRaises(OSError): исполнитель.установить()
            сам.assertTrue((сам.папка / 'запрос.md').is_file())
            сам.assertFalse((сам.папка / 'отчёт.md').exists())
            with mock.patch.object(журнал_приёма.план, 'подготовить', side_effect=AssertionError('Повтор renderer')):
                сам.assertEqual(журнал_приёма.ЖурналПриёма(приём).установить()['состояние'], 'установлено')

    def test_чужие_байты_при_частичной_установке_не_переписываются(сам):
        with сам.ф.приём() as приём:
            приём.применить()
            исполнитель = журнал_приёма.ЖурналПриёма(приём)
            def остановить(точка):
                if точка == 'запрос.md': raise OSError('Прервано')
            with mock.patch.object(исполнитель, '_граница', side_effect=остановить):
                with сам.assertRaises(OSError): исполнитель.установить()
            (сам.папка / 'запрос.md').write_text('Сохранить правку')
            with сам.assertRaises(ValueError): исполнитель.установить()
            сам.assertFalse((сам.папка / 'отчёт.md').exists())
            сам.assertEqual((сам.папка / 'запрос.md').read_text(), 'Сохранить правку')

    def test_повтор_после_заполнения_не_переписывает_отчёт(сам):
        with сам.ф.приём() as приём:
            приём.применить(); исполнитель = журнал_приёма.ЖурналПриёма(приём)
            первый = исполнитель.установить()
            отчёт = сам.папка / 'отчёт.md'; отчёт.write_text('Содержательный результат\n')
            до = отчёт.stat().st_mtime_ns
            with mock.patch.object(журнал_приёма.план, 'подготовить', side_effect=AssertionError('Повтор renderer')):
                сам.assertEqual(первый, исполнитель.установить())
            сам.assertEqual(отчёт.read_text(), 'Содержательный результат\n')
            сам.assertEqual(отчёт.stat().st_mtime_ns, до)
            отчёт.unlink()
            with сам.assertRaises(ValueError): исполнитель.установить()
            сам.assertFalse(отчёт.exists())

    def test_занятый_журнал_не_усыновляется(сам):
        with сам.ф.приём() as приём:
            приём.применить(); сам.папка.mkdir(parents=True)
            with сам.assertRaises(ValueError): журнал_приёма.ЖурналПриёма(приём).установить()
            сам.assertEqual(list(сам.папка.iterdir()), [])

    def test_подмена_или_потеря_намерения_сохраняет_отказ(сам):
        with сам.ф.приём() as приём:
            приём.применить(); исполнитель = журнал_приёма.ЖурналПриёма(приём)
            исполнитель.установить()
            путь = эпизод.путь_эпизода(сам.ф.основание).with_suffix('.журнал.json')
            данные = путь.read_bytes(); путь.unlink()
            with сам.assertRaises(ValueError): исполнитель.установить()
            путь.write_bytes(данные); путь.chmod(0o600)
            конверт = эпизод.хранение.разобрать(данные)
            конверт['данные']['состояние'] = 'устанавливается'
            конверт['sha256'] = эпизод.хранение.хэш(конверт['данные'])
            путь.write_bytes(эпизод.хранение.байты(конверт))
            (сам.папка / 'отчёт.md').write_text('После заполнения')
            with сам.assertRaises(ValueError): исполнитель.установить()
            сам.assertEqual((сам.папка / 'отчёт.md').read_text(), 'После заполнения')


if __name__ == '__main__':
    unittest.main()

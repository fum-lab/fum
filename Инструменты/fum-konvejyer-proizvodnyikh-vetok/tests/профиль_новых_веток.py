"""Профиль подготовки преемника; исходные остановленные деревья сохраняются."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from фикстура_новых_веток import новое_поколение
import запуск_слоёв


def измерить():
    фазы = []
    def замер(имя, действие):
        начало = time.perf_counter_ns()
        значение = действие()
        фазы.append({'стадия': имя, 'наносекунды': time.perf_counter_ns() - начало})
        return значение
    with новое_поколение() as (_, объект, _, вход, _, _, _):
        план = замер('предпросмотр', lambda: объект.предпросмотр(вход))
        итог = замер('подготовка под замком', lambda: объект.подготовить(вход, план['sha256']))
        assert итог == план
        for слой in ('события', 'сообщения'):
            допуск = замер('допуск: ' + слой, lambda: объект.допустить(вход, слой))
            assert допуск['разрешён_вызов']
            до = объект.хранилище.путь.read_bytes()
            повтор = замер('повтор допуска: ' + слой, lambda: объект.допустить(вход, слой))
            assert not повтор['разрешён_вызов'] and повтор['попытка'] == допуск['попытка']
            assert до == объект.хранилище.путь.read_bytes()
    assert all(hashlib.sha256(п.read_bytes()).hexdigest() == х for п, х in запуск_слоёв.КОД.items())
    return {'схема': 'fum.профиль-новых-веток-поколения.1', 'фазы': фазы,
            'исходники_sha256': {п.name: х for п, х in запуск_слоёв.КОД.items()},
            'граница': 'Открытая Git-фикстура с двумя сохранёнными писателями; подготовка исключена. '
                       'Совпадение checkout кода подменено. Один замер на фазу; Desktop и сеть не вызываются. '
                       'Повтор допуска подтверждает отсутствие второй внешней попытки, а не новую доставку.'}


if __name__ == '__main__':
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--выход', required=True, type=Path)
    параметры = парсер.parse_args()
    итог = измерить()
    with параметры.выход.open('x', encoding='utf-8') as поток:
        поток.write(json.dumps(итог, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(итог, ensure_ascii=False))

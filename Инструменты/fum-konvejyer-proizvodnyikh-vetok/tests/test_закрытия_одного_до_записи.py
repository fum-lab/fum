"""Терминал .6 сохраняет одну реальную попытку и отсутствие второго допуска."""
import copy
import importlib
import hashlib
import json
from pathlib import Path
import unittest
from unittest import mock

from фикстура_барьера_запуска import один_до_записи, обновить
from фикстура_двух_до_записи import первичный_вызов
from test_запуска_слоёв import хранение
import терминал_запуска


class ПроверкаЗакрытияОдного(unittest.TestCase):
    def модуль(self): return importlib.import_module('завершение_одного_до_записи')

    def test_добавлен_только_терминал_повтор_не_читает_живые_источники(self):
        with один_до_записи() as (_,объект,_,план,вход,_,ребёнок):
            модуль=self.модуль();до=объект.хранилище.прочитать()
            результат=модуль.предпросмотр(объект,вход)
            self.assertEqual('fum.завершённый-неудачный-запуск.6',результат['схема'])
            self.assertFalse(результат['отсутствие_незаписанного_вызова_доказано'])
            self.assertEqual({'вид':'не-допущен'},результат['слои']['сообщения'])
            self.assertEqual(результат,модуль.завершить(объект,вход,результат['sha256']))
            после=объект.хранилище.прочитать();ключ=терминал_запуска.ключ(план['запуск'])
            self.assertEqual(результат,после['приёмы'].pop(ключ))
            self.assertEqual(до,после)
            ребёнок[2].unlink();Path(вход['источник']['путь']).unlink()
            self.assertEqual(результат,модуль.завершить(объект,вход,результат['sha256']))

    def test_второй_реальный_create_не_подменяет_отсутствие_допуска(self):
        with один_до_записи() as (_,объект,_,план,вход,события,_):
            события.insert(2,первичный_вызов('create_thread','создать-сообщения',план['аргументы']['сообщения'],{'content':[{'type':'text','text':json.dumps({'threadId':'00000000-0000-4000-8000-000000000002'})}],'isError':False},15))
            обновить(вход,события)
            with self.assertRaises(хранение.ОшибкаПриёма): self.модуль().предпросмотр(объект,вход)

    def test_вторая_локальная_попытка_закрывает_минимальный_путь(self):
        with один_до_записи() as (_,объект,_,план,вход,_,_):
            with объект.хранилище.изменить() as состояние:
                попытка=copy.deepcopy(состояние['попытки'][план['попытки']['события']])
                попытка.update(попытка='00000000-0000-4000-8000-000000000002',ответ=None,состояние='исход неизвестен');попытка['аргументы']=план['аргументы']['сообщения'];попытка['аргументы_sha256']=хранение.хэш(попытка['аргументы'])
                состояние['попытки'][план['попытки']['сообщения']]=попытка
            with self.assertRaises(хранение.ОшибкаПриёма): self.модуль().предпросмотр(объект,вход)

    def test_грязное_дерево_или_созданный_ref_не_являются_остановкой_до_записи(self):
        for вид in ('грязное','ветка'):
            with self.subTest(вид=вид),один_до_записи() as (_,объект,_,план,вход,_,ребёнок):
                if вид=='грязное': (ребёнок[0]/'правка.txt').write_text('не завершено')
                else:
                    ref=next(с['ветка'] for с in план['описание']['слои'] if с['слой']=='события')
                    хранение.гит(ребёнок[0],'switch','-c',ref.removeprefix('refs/heads/'))
                with self.assertRaises(хранение.ОшибкаПриёма): self.модуль().предпросмотр(объект,вход)

    def test_устаревшее_ожидание_и_чужой_UUID_отклоняются(self):
        for вид in ('ожидание','UUID'):
            with self.subTest(вид=вид),один_до_записи() as (_,объект,_,_,вход,события,_):
                иной=copy.deepcopy(вход)
                if вид=='ожидание': иной['ожидания'][иной['слои']['события']['задача']]='старое-ожидание'
                else: иной['слои']['события']['задача']='00000000-0000-4000-8000-000000000099'
                with self.assertRaises(хранение.ОшибкаПриёма): self.модуль().предпросмотр(объект,иной)

    def test_сдвиг_после_предпросмотра_не_сохраняет_терминал(self):
        with один_до_записи() as (_,объект,_,план,вход,_,ребёнок):
            модуль=self.модуль();результат=модуль.предпросмотр(объект,вход)
            ребёнок[2].write_bytes(ребёнок[2].read_bytes()+b'{}\n')
            with self.assertRaises(хранение.ОшибкаПриёма): модуль.завершить(объект,вход,результат['sha256'])
            self.assertNotIn(терминал_запуска.ключ(план['запуск']),объект.хранилище.прочитать()['приёмы'])

    def test_отказ_первоначальных_прав_позволяет_честное_закрытие(self):
        политика={'approval_policy':'on-request','sandbox_policy':{'type':'workspace-write'}}
        with один_до_записи(политика=политика) as (_,объект,_,план,вход,_,_):
            ключ=план['попытки']['сообщения']
            self.assertNotIn(ключ,объект.хранилище.прочитать()['попытки'])
            результат=self.модуль().предпросмотр(объект,вход)
            self.модуль().завершить(объект,вход,результат['sha256'])
            self.assertNotIn(ключ,объект.хранилище.прочитать()['попытки'])

    def test_сдвиги_именно_под_замком_сохраняют_байты_реестра(self):
        with один_до_записи() as (корень,объект,_,план,вход,_,ребёнок):
            модуль=self.модуль();результат=модуль.предпросмотр(объект,вход);исходная=модуль._план
            до=объект.хранилище.путь.read_bytes()
            rootpath=Path(вход['источник']['путь']);rootbytes=rootpath.read_bytes();childbytes=ребёнок[2].read_bytes()
            ref=next(с['ветка'] for с in план['описание']['слои'] if с['слой']=='события');короткий=ref.removeprefix('refs/heads/')
            for вид in ('корень','ребёнок','ref','вторая-попытка','писатель'):
                with self.subTest(вид=вид):
                    def сдвинуть(*аргументы):
                        r=исходная(*аргументы);состояние=аргументы[2]
                        if вид=='корень': rootpath.write_bytes(rootbytes.replace(b'completed',b'completex'))
                        elif вид=='ребёнок': ребёнок[2].write_bytes(childbytes+b'{}\n')
                        elif вид=='ref': хранение.гит(корень,'branch',короткий,план['координатор']['HEAD'])
                        elif вид=='писатель': состояние['писатели'][str(ребёнок[0])]={'задача':ребёнок[1],'ref':ref}
                        else:
                            p=copy.deepcopy(состояние['попытки'][план['попытки']['события']]);p.update(попытка='00000000-0000-4000-8000-000000000002',ответ=None,состояние='исход неизвестен')
                            p['аргументы']=план['аргументы']['сообщения'];p['аргументы_sha256']=хранение.хэш(p['аргументы'])
                            состояние['попытки'][план['попытки']['сообщения']]=p
                        return r
                    with mock.patch.object(модуль,'_план',side_effect=сдвинуть),self.assertRaises(хранение.ОшибкаПриёма):
                        модуль.завершить(объект,вход,результат['sha256'])
                    self.assertEqual(до,объект.хранилище.путь.read_bytes())
                    rootpath.write_bytes(rootbytes);ребёнок[2].write_bytes(childbytes)
                    if вид=='ref': хранение.гит(корень,'branch','-D',короткий)

    def test_терминал_принимает_преемник_с_новым_C_и_точным_SHA(self):
        from фикстура_новых_веток import закрепить
        from test_запуска_слоёв import сформировать_ref_ветки
        with один_до_записи() as (корень,объект,пакет,план,вход,_,_):
            модуль=self.модуль();результат=модуль.предпросмотр(объект,вход);модуль.завершить(объект,вход,результат['sha256'])
            новый=copy.deepcopy(пакет);ссылка={'запуск':план['запуск'],'терминал_sha256':результат['sha256']};новый['предыдущий']=ссылка
            описание=copy.deepcopy(план['описание']);описание['предыдущий']=ссылка
            for слой in описание['слои']: слой['ветка']=сформировать_ref_ветки(слой['каталог'],'codex')+'--g-'+результат['sha256']
            назначение=хранение.разобрать((корень/новый['назначение']).read_bytes())
            назначение['журналы']={с:к.replace('12-30-00','13-00-00') for с,к in назначение['журналы'].items()}
            данные=хранение.байты(назначение);(корень/новый['назначение']).write_bytes(данные);новый['постановка']['файлы'][новый['назначение']]=hashlib.sha256(данные).hexdigest()
            закрепить(корень,новый,описание)
            ложный=copy.deepcopy(новый);ложный['предыдущий']['терминал_sha256']='0'*64
            with self.assertRaises(хранение.ОшибкаПриёма): объект.предпросмотр(ложный)
            до=объект.хранилище.прочитать();преемник=объект.предпросмотр(новый);объект.подготовить(новый,преемник['sha256'])
            после=объект.хранилище.прочитать();self.assertEqual(до['попытки'],после['попытки'])
            for ключ,запись in до['приёмы'].items():self.assertEqual(запись,после['приёмы'][ключ])
            with self.assertRaises(хранение.ОшибкаПриёма): объект.сохранить(план['запуск'],'события',вход['слои']['события']['попытка'],{'threadId':вход['слои']['события']['задача']})



"""Открытый профиль двух границ чтения; слияние и сеть не измеряются."""
import argparse
import hashlib
import json
from pathlib import Path
import time

from фикстура_дочернего_коммита import фикстура
import дочернее_назначение as назначение


def измерить():
    результаты = []
    with фикстура() as (корень, источник, параметры):
        задача = параметры['исполнитель']
        операции = {'полная область': назначение.прочитать,
                    'первоначальное основание': назначение.прочитать_основание}
        ожидаемая = None
        for повтор in range(3):
            порядок = list(операции) if повтор % 2 == 0 else list(reversed(операции))
            for имя in порядок:
                начало = time.perf_counter_ns()
                итог = операции[имя](корень, задача, источник)
                время = time.perf_counter_ns() - начало
                привязка = назначение.привязка(итог)
                if ожидаемая is None:
                    ожидаемая = привязка
                assert привязка == ожидаемая and итог['разрешение_записи'] is False
                assert ('снимок' in итог) == (имя == 'полная область')
                результаты.append({'повтор': повтор + 1, 'режим': имя,
                    'длительность_наносекунды': время})
    исходники = Path(назначение.__file__).parent
    return {'схема': 'fum.профиль-оснований-приёма.1', 'измерения': результаты,
        'исходники_sha256': {имя: hashlib.sha256((исходники / имя).read_bytes()).hexdigest()
            for имя in ('дочернее_назначение.py', 'нативные_вызовы.py')},
        'одинаковая_неизменяемая_привязка': True,
        'граница': 'Открытая Git-фикстура; подготовка исключена. Разные гарантии чтения, '
            'не сравнение равноценных допусков. Обратный merge, сеть и Desktop не измерены.'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--выход', type=Path, required=True)
    путь = parser.parse_args().выход
    данные = измерить()
    with путь.open('x', encoding='utf-8') as файл:
        json.dump(данные, файл, ensure_ascii=False, indent=2)
        файл.write('\n')
    print(json.dumps({'измерений': len(данные['измерения']), 'граница': данные['граница']}, ensure_ascii=False))

"""Атомарная смена размещения не возобновляет старые стадии и вызовы."""
import copy
import importlib
from contextlib import contextmanager
from pathlib import Path
import unittest

from фикстура_новых_веток import новое_поколение, хранение
from test_запуска_слоёв import исполнитель
from test_входа_направления import сообщение, строка


@contextmanager
def переход_фикстура():
    with новое_поколение() as (корень, прежний, старый, новый, описание, терминал, _):
        получатель = корень.parent / 'получатель'
        отсутствующий = корень.parent / 'прежняя-fuma'
        хранение.гит(корень, 'worktree', 'add', '-qb', 'fuma', str(получатель), 'HEAD')
        with прежний.хранилище.изменить() as состояние:
            состояние['писатели'][str(отсутствующий)] = {'задача': прежний.задача, 'ref': 'refs/heads/fuma'}
            for размещение, ветка in ((отсутствующий, 'refs/heads/fuma'), (корень, новый['постановка']['ветка'])):
                for номер in range(2):
                    событие = str(размещение) + '-' + str(номер)
                    ключ = хранение.ключ_этапа(событие, 'диагностика')
                    состояние['этапы'][ключ] = {
                        'событие': событие, 'этап': 'диагностика', 'задача': прежний.задача,
                        'корень': str(размещение), 'ref': ветка, 'база': новый['постановка']['коммит'],
                        'готов': True, 'коммит': None,
                        'файлы': {'Планирование/диагностика.md': {'до': None, 'после': 'Незавершённое\n'}}}
        объект = исполнитель(получатель)
        решение = copy.deepcopy(новый['решение'])
        решение.update(задача=None, действие='обновить', объём='реализация')
        пакет = {
            'схема': 'fum.вход-перехода-координатора.1', 'задача': прежний.задача,
            'предыдущий': новый['предыдущий'],
            'прежний_координатор': прежний.хранилище._наблюдать_владельца(),
            'прежнее_размещение': {'задача': прежний.задача, 'путь': str(отсутствующий), 'ref': 'refs/heads/fuma'},
            'получатель': объект.хранилище._наблюдать_владельца(),
            'источник': новый['источник'], 'решение': решение,
            'свидетельство_координатора': {
                'задача': прежний.задача, 'единственный_координатор': True,
                'нет_незаписанных_или_выполняющихся_вызовов_этой_цепочки': True,
                'прежняя_цепочка_не_возобновляется': True}}
        yield объект, прежний, пакет, старый, новый, описание


class ПроверкаПереходаКоординатора(unittest.TestCase):
    def переход(сам, объект, пакет):
        модуль = importlib.import_module('переход_координатора')
        план = модуль.предпросмотр(объект, пакет)
        результат = модуль.перейти(объект, пакет, план['sha256'])
        сам.assertEqual(план, результат)
        return модуль, план

    def test_атомарный_переход_сохраняет_историю_и_побайтный_повтор(сам):
        with переход_фикстура() as (объект, прежний, пакет, старый, _, _):
            до = прежний.хранилище.прочитать()
            with сам.assertRaises(ValueError): объект.хранилище.занять()
            модуль, план = сам.переход(объект, пакет)
            после = объект.хранилище.прочитать()
            сам.assertEqual(до['этапы'], после['этапы'])
            сам.assertEqual(до['попытки'], после['попытки'])
            сам.assertEqual(до['приёмы'][старый['запуск']], после['приёмы'][старый['запуск']])
            сам.assertNotIn(пакет['прежнее_размещение']['путь'], после['писатели'])
            сам.assertIn(str(прежний.корень), после['писатели'])
            сам.assertIn(str(объект.корень), после['писатели'])
            сам.assertEqual(после['схема'], 'fum.приём-направлений.2')
            with сам.assertRaises(ValueError): объект._прочитать(после, старый['запуск'])
            сам.assertEqual(до['приёмы'][старый['запуск']], объект._прочитать_предшественника(после, старый['запуск']))
            байты = объект.хранилище.путь.read_bytes()
            сам.assertEqual(план, модуль.перейти(объект, пакет, план['sha256']))
            сам.assertEqual(байты, объект.хранилище.путь.read_bytes())

    def test_закрытая_история_и_квитанции_не_меняются_через_общий_API(сам):
        with переход_фикстура() as (объект, прежний, пакет, старый, _, _):
            сам.переход(объект, пакет)
            до = объект.хранилище.путь.read_bytes()
            попытка = объект.хранилище.прочитать()['попытки'][старый['попытки']['события']]
            with сам.assertRaises(ValueError):
                прежний.хранилище.сохранить_ответ(старый['попытки']['события'], попытка['попытка'], {'новый': True})
            with сам.assertRaises(ValueError):
                with объект.хранилище.изменить() as состояние:
                    состояние['приёмы'] = {к: в for к, в in состояние['приёмы'].items()
                                          if в.get('схема') not in {'fum.переход-координатора.1', 'fum.перенос-привязки-писателя.1'}}
            with сам.assertRaises(ValueError):
                with объект.хранилище.изменить() as состояние:
                    состояние['схема'] = 'fum.приём-направлений.1'
                    состояние['писатели'][пакет['прежнее_размещение']['путь']] = состояние['писатели'].pop(str(объект.корень))
                    состояние['приёмы'] = {к: в for к, в in состояние['приёмы'].items()
                                          if в.get('схема') not in {'fum.переход-координатора.1', 'fum.перенос-привязки-писателя.1'}}
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_прежний_координатор_не_создаёт_преемника_после_перехода(сам):
        with переход_фикстура() as (объект, прежний, пакет, _, новый, _):
            сам.переход(объект, пакет)
            до = объект.хранилище.путь.read_bytes()
            with сам.assertRaisesRegex(ValueError, 'передан|координатор'):
                прежний.предпросмотр(новый)
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_дрейф_HEAD_или_человеческого_ввода_не_сохраняет_переход(сам):
        with переход_фикстура() as (объект, _, пакет, _, _, _):
            модуль = importlib.import_module('переход_координатора')
            план = модуль.предпросмотр(объект, пакет)
            до = объект.хранилище.путь.read_bytes()
            with Path(пакет['источник']).open('ab') as поток:
                поток.write(строка(сообщение('Отменить переход', 'позднее')))
            with сам.assertRaises(ValueError): модуль.перейти(объект, пакет, план['sha256'])
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())
        with переход_фикстура() as (объект, _, пакет, _, _, _):
            план = модуль.предпросмотр(объект, пакет)
            до = объект.хранилище.путь.read_bytes()
            хранение.гит(объект.корень, 'commit', '--allow-empty', '-qm', 'Сдвиг получателя')
            with сам.assertRaises(ValueError): модуль.перейти(объект, пакет, план['sha256'])
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_другой_получатель_и_незакрытый_предок_не_разрешены(сам):
        with переход_фикстура() as (объект, _, пакет, _, _, _):
            модуль, план = сам.переход(объект, пакет)
            иной = copy.deepcopy(пакет); иной['получатель']['HEAD'] = 'f' * 40
            до = объект.хранилище.путь.read_bytes()
            with сам.assertRaises(ValueError): модуль.перейти(объект, иной, план['sha256'])
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())
        with переход_фикстура() as (объект, _, пакет, старый, _, _):
            import терминал_запуска
            with объект.хранилище.изменить() as состояние:
                del состояние['приёмы'][терминал_запуска.ключ(старый['запуск'])]
            до = объект.хранилище.путь.read_bytes()
            with сам.assertRaises(ValueError): модуль.предпросмотр(объект, пакет)
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_архивный_этап_не_исчезает_и_прежнее_дерево_не_возрождается(сам):
        with переход_фикстура() as (объект, _, пакет, _, _, _):
            модуль = importlib.import_module('переход_координатора')
            Path(пакет['прежнее_размещение']['путь']).mkdir()
            до = объект.хранилище.путь.read_bytes()
            with сам.assertRaises(ValueError): модуль.предпросмотр(объект, пакет)
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())
        with переход_фикстура() as (объект, _, пакет, _, _, _):
            сам.переход(объект, пакет)
            до = объект.хранилище.путь.read_bytes()
            with сам.assertRaises(ValueError):
                with объект.хранилище.изменить() as состояние:
                    ключ = next(к for к, в in состояние['этапы'].items() if в['корень'] == пакет['прежнее_размещение']['путь'])
                    del состояние['этапы'][ключ]
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())
            хранение.гит(объект.корень, 'worktree', 'add', '-qb', 'codex/возрождённая', пакет['прежнее_размещение']['путь'], 'HEAD')
            архивный = хранение.Хранилище(пакет['прежнее_размещение']['путь'], объект.задача)
            with сам.assertRaises(ValueError): архивный.занять()
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_исторический_recovery_ref_сохраняется_отдельно(сам):
        with переход_фикстура() as (объект, _, пакет, старый, _, _):
            import терминал_запуска
            with объект.хранилище.изменить() as состояние:
                терминал = состояние['приёмы'][терминал_запуска.ключ(старый['запуск'])]
                терминал['координатор']['ref'] = 'refs/heads/codex/восстановление'
                терминал['sha256'] = хранение.хэш({к: в for к, в in терминал.items() if к != 'sha256'})
                пакет['предыдущий']['терминал_sha256'] = терминал['sha256']
            _, план = сам.переход(объект, пакет)
            сам.assertEqual('refs/heads/codex/восстановление', план['координатор']['квитанция']['цепочка'][0]['координатор_терминала']['ref'])

    def test_новый_C_не_может_обойти_принятый_коммит_перехода(сам):
        with переход_фикстура() as (объект, _, пакет, старый, _, _):
            сам.переход(объект, пакет)
            состояние = объект.хранилище.прочитать()
            import терминал_запуска
            старый_C = состояние['приёмы'][терминал_запуска.ключ(старый['запуск'])]['координатор']['HEAD']
            дерево = хранение.гит(объект.корень, 'rev-parse', 'HEAD^{tree}').strip()
            обход = хранение.гит(объект.корень, 'commit-tree', дерево, '-p', старый_C, вход=b'Unrelated fixture parent\n').strip()
            with сам.assertRaises(ValueError): объект._прочитать_предшественника(состояние, старый['запуск'], новый_C=обход)

    def test_диагностика_прежнего_координатора_остаётся_незавершённой_и_доступной(сам):
        with переход_фикстура() as (объект, прежний, пакет, _, _, _):
            сам.переход(объект, пакет)
            with прежний.хранилище.изменить() as состояние:
                этап = next(в for в in состояние['этапы'].values() if в['корень'] == str(прежний.корень))
                этап['файлы']['Планирование/диагностика.md']['после'] += 'Уточнение\n'
            состояние = объект.хранилище.прочитать()
            сам.assertTrue(all(в['коммит'] is None for в in состояние['этапы'].values()))
            сам.assertIn(str(прежний.корень), состояние['писатели'])


if __name__ == '__main__':
    unittest.main()

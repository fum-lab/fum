    def test_возобновление_до_завершения_ожидания_также_отклоняется(self):
        with пилот() as (_, объект, _, _, вход, события, _):
            задача = вход["слои"]["события"]["задача"]
            начало_ожидания = copy.deepcopy(события[-1])
            начало_ожидания["payload"]["type"] = "item_started"
            завершение = вызов("send_message_to_thread", "возобновить", {"threadId": задача, "prompt": "Продолжай"}, {"content": [], "isError": False})
            начало = copy.deepcopy(завершение)
            начало["payload"]["type"] = "item_started"
            события[-1:] = [начало_ожидания, начало, завершение, события[-1]]
            путь = Path(вход["источник"]["путь"])
            путь.write_bytes(b"".join(строка(з) for з in события))
            вход["источник"] = граница(путь, корень=True)
            with self.assertRaisesRegex(ValueError, "возобновление"):
                self.модуль().предпросмотр(объект, вход)

    def test_Git_сверяется_повторно_непосредственно_перед_терминалом(self):
        for вид in ("held-ref", "детская-ветка", "ранняя-квитанция"):
            with self.subTest(вид=вид), пилот() as (корень, объект, пакет, план, вход, _, _):
                м = self.модуль()
                результат = м.предпросмотр(объект, вход)
                исходная = м.остановка_ребёнка.проверить
                def сдвинуть(*а):
                    наблюдение = исходная(*а)
                    if вид == "held-ref":
                        хранение.гит(корень, "update-ref", пакет["постановка"]["ветка"], вход["координатор"]["HEAD"])
                    elif вид == "детская-ветка":
                        хранение.гит(корень, "update-ref", план["описание"]["слои"][0]["ветка"], пакет["постановка"]["коммит"])
                    else:
                        м.остановка_ребёнка.постановка.путь_подтверждения(Path(вход["слои"]["события"]["корень"])).write_text("{}")
                    return наблюдение
                до = объект.хранилище.путь.read_bytes()
                with mock.patch.object(м.остановка_ребёнка, "проверить", side_effect=сдвинуть), self.assertRaises(ValueError):
                    м.завершить(объект, вход, результат["sha256"])
                self.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_CLI_не_принимает_чужой_или_отсутствующий_native_UUID(self):
        cli = Path(__file__).resolve().parents[1] / "scripts/запустить-слои.py"
        for значение in (None, "00000000-0000-4000-8000-000000000099"):
            среда = dict(os.environ)
            среда.pop("CODEX_THREAD_ID", None)
            if значение:
                среда["CODEX_THREAD_ID"] = значение
            результат = subprocess.run([sys.executable, "-B", str(cli), "--корень-репозитория", ".", "--задача", ЗАДАЧА,
                                        "завершить", "--вход", "не-читать.json", "--sha256", "0" * 64], env=среда, capture_output=True)
            self.assertEqual(результат.returncode, 2)
            self.assertIn("Нативный UUID", результат.stdout.decode())



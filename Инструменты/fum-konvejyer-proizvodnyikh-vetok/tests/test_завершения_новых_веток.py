"""Оба конечных случая запуска v4 сохраняют старое поколение и своих детей."""
import copy
from pathlib import Path
import unittest

from фикстура_новых_веток import новое_поколение, хранение
from фикстура_остановленного_поколения import подготовить_остановку
from test_завершения_запуска import остановить_до_назначения
from test_запуска_слоёв import ребёнок
import завершение_запуска
import завершение_сохранённых_писателей
import терминал_запуска


def снимки(дети):
    return {str(дерево): {
        'HEAD': хранение.гит(дерево, 'rev-parse', 'HEAD'),
        'ref': хранение.гит(дерево, 'rev-parse', '--abbrev-ref', 'HEAD'),
        'индекс': хранение.гит(дерево, 'ls-files', '--stage', '-z'),
        'состояние': хранение.гит(дерево, 'status', '--porcelain', '-z'),
        'источник': источник.read_bytes(),
        'байты': {str(п.relative_to(дерево)): п.read_bytes() for п in (дерево / 'Память').rglob('поток.jsonl')},
    } for дерево, _, источник in дети.values()}


class ПроверкаЗавершенияНовыхВеток(unittest.TestCase):
    def завершить_и_повторить(сам, модуль, объект, вход):
        до = объект.хранилище.прочитать()
        результат = модуль.предпросмотр(объект, вход)
        сам.assertEqual(до, объект.хранилище.прочитать())
        сам.assertEqual(результат, модуль.завершить(объект, вход, результат['sha256']))
        после = объект.хранилище.прочитать()
        del после['приёмы'][терминал_запуска.ключ(вход['запуск'])]
        сам.assertEqual(до, после)
        байты = объект.хранилище.путь.read_bytes()
        сам.assertEqual(результат, модуль.завершить(объект, вход, результат['sha256']))
        сам.assertEqual(байты, объект.хранилище.путь.read_bytes())

    def test_чистый_неназначенный_ребёнок_и_неиспользованный_допуск_v4(сам):
        with новое_поколение() as (корень, объект, _, запуск, _, _, прежние):
            до = снимки(прежние)
            план = объект.предпросмотр(запуск); объект.подготовить(запуск, план['sha256'])
            вход, _, _ = остановить_до_назначения(корень, объект, запуск, план)
            слой = вход['слои']['события']
            новые = {'события': (Path(слой['корень']), слой['задача'], Path(слой['источник']['путь']))}
            остановленный = снимки(новые)
            сам.завершить_и_повторить(завершение_запуска, объект, вход)
            сам.assertEqual(до, снимки(прежние))
            сам.assertEqual(остановленный, снимки(новые))

    def test_оба_назначенных_писателя_v4_с_пакетами(сам):
        with новое_поколение() as (корень, объект, _, запуск, описание, _, прежние):
            до = снимки(прежние)
            план = объект.предпросмотр(запуск); объект.подготовить(запуск, план['sha256'])
            дети = {}
            for номер, слой in enumerate(описание['слои'], 101):
                имя = слой['слой']; допуск = объект.допустить(запуск, имя)
                дети[имя] = ребёнок(корень, запуск, слой, допуск, номер, экранировать=True)
                объект.наблюдать(план['запуск'], имя, *дети[имя])
            назначение = хранение.разобрать((корень / запуск['назначение']).read_bytes())
            вход, _ = подготовить_остановку(корень, объект, запуск, план, назначение, дети)
            новые = снимки(дети)
            иной = copy.deepcopy(вход); иной['слои']['события']['пакет'] = иной['слои']['сообщения']['пакет']
            модуль = завершение_сохранённых_писателей
            with сам.assertRaises(ValueError): модуль.предпросмотр(объект, иной)
            сам.завершить_и_повторить(модуль, объект, вход)
            сам.assertEqual(до, снимки(прежние))
            сам.assertEqual(новые, снимки(дети))


if __name__ == '__main__':
    unittest.main()

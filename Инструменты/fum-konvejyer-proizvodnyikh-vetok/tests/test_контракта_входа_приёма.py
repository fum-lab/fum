"""Недопустимые параметры должны отказывать ещё до нативного допуска и эффекта."""
import os
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import вход_приёма as вход


class ПроверкаКонтрактаВхода(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory(); сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name).resolve()
        сам.задача = '22222222-2222-4222-8222-222222222222'
        сам.блок = {'схема': 'fum.поручение-дочернего-приёма.1',
            'корневая_задача': '11111111-1111-4111-8111-111111111111', 'исполнитель': сам.задача,
            'база': 'a' * 40, 'исходный_коммит': 'b' * 40, 'срез': 'c' * 40,
            'источник_приёмки': 'd' * 40, 'назначение_sha256': 'e' * 64, 'план': 'f' * 64,
            'слой': 'слой', 'корень': str(сам.корень), 'ref': 'refs/heads/codex/слой',
            'журнал': 'Журнал/2026-09-24_12-00-00_MSK_приём/',
            'проверка': '33333333-3333-4333-8333-333333333333'}
        сам.данные = {'схема': 'fum.вход-дочернего-приёма.1', 'источник': str(сам.корень/'отсутствует.jsonl'),
            'текст': вход.приём_интеграции.сформировать(сам.блок), 'план': {}, 'свидетельство': {},
            'реестр': str(сам.корень/'отсутствует.json'),
            'коммит': {'имя_автора': 'FUM Писатель', 'заголовок': 'Принять срез', 'описание': 'Точный импорт'}}
        сам.файл = сам.корень/'вход.json'

    def прочитать(сам, данные):
        сам.файл.write_bytes(вход.хранение.байты(данные))
        with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': сам.задача}):
            return вход.прочитать(сам.файл, сам.корень)

    def test_роль_проверяется_до_начала_эпизода(сам):
        with сам.assertRaisesRegex(ValueError, 'рол'):
            сам.прочитать({**сам.данные, 'коммит': {**сам.данные['коммит'], 'имя_автора': 'writer'}})
        сам.assertEqual(list(сам.корень.iterdir()), [сам.файл])
        # Исправленный вход того же эпизода не заблокирован ранним отказом.
        сам.assertEqual(сам.прочитать(сам.данные)[1], сам.блок)

    def test_заголовок_не_допускает_новую_строку(сам):
        with сам.assertRaises(ValueError):
            сам.прочитать({**сам.данные, 'коммит': {**сам.данные['коммит'], 'заголовок': 'Первый\nВторой'}})

    def test_нельзя_добавить_вызываемую_функцию_или_готовое_основание(сам):
        for ключ in ('callback', 'основание', 'подготовка', 'разрешённые_цели'):
            with сам.subTest(ключ=ключ), сам.assertRaises(ValueError):
                сам.прочитать({**сам.данные, ключ: 'недоверенные данные'})

    def test_повторный_ключ_формата_отказывает(сам):
        сырые = вход.хранение.байты(сам.данные)
        сам.файл.write_bytes(b'{"schema":1,"schema":2,'+сырые[1:])
        with сам.assertRaisesRegex(ValueError, 'JSON'):
            вход.прочитать(сам.файл, сам.корень)


if __name__ == '__main__':
    unittest.main()

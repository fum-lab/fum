"""Измерить дополнительную Git-сверку поверх удерживаемого файлового снимка."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import statistics
import tempfile
import time
from unittest import mock

from фикстура_исторического_отказа import ФикстураИсторическогоОтказа, хранение
import архивный_префикс_приёма as архивы
import конверт_приёма as конверт
import эпизод_приёма as эпизод
import прочитать_исторический_отказ as читатель


def выполнить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--выход', type=Path, required=True)
    аргументы = парсер.parse_args()
    with tempfile.TemporaryDirectory(prefix='fum-профиль-Git-сверки-') as временное:
        ф = ФикстураИсторическогоОтказа(временное)
        корневой_файл = ф.приватное / 'ROOT-профиля.jsonl'; данные = b'root\n'
        корневой_файл.write_bytes(данные); корневой_файл.chmod(0o400)
        описание = {'путь': str(корневой_файл), 'начало': len(данные), 'граница': len(данные),
            'начало_sha256': hashlib.sha256(данные).hexdigest(), 'sha256': hashlib.sha256(данные).hexdigest()}
        прежний, новый = архивы.АрхивыПриёма(описание), архивы.АрхивыПриёма(описание)
        with mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', ф.приватное), \
                mock.patch.object(эпизод, 'КОРЕНЬ_СОСТОЯНИЯ', ф.приватное / 'эпизоды'):
            исходный = читатель.прочитать(ф.описание_чтения, ф.текст, ф.нативный, сверки=новый)
            assert len(новый.дочерние_сверки) == 3
            # Два файловых callback сохраняются; третий добавляет полную Git-сверку.
            for проверка in новый.дочерние_сверки[:2]: прежний.сохранить_сверку(проверка)
            def измерить(снимок, режим):
                начало = time.monotonic_ns(); снимок.сверить()
                return {'режим': режим, 'длительность_нс': time.monotonic_ns() - начало}
            режимы = [(прежний, 'файлы'), (новый, 'файлы-и-Git')]
            прогрев = [измерить(*п) for п in режимы]; серии = []
            for номер in range(3):
                for снимок, режим in (режимы if номер % 2 == 0 else list(reversed(режимы))):
                    серии.append(dict(измерить(снимок, режим), повтор=номер + 1))
            assert читатель.прочитать(ф.описание_чтения, ф.текст, ф.нативный) == исходный
            результат = {'схема': 'fum.профиль-заключительной-Git-сверки.1',
                'граница': 'Один получатель открытой FS/Git-фикстуры; повторная сверка без построения фикстуры, native-разбора, Desktop и записи терминала',
                'ограничение': 'Режим файлы оставляет прежний пропуск Git-сверки; это не допустимая защита и не сравнение полного цикла',
                'вход_sha256': хранение.хэш(исходный), 'входы_неизменны': True,
                'код_sha256': читатель.КОД_ПРИ_ЗАГРУЗКЕ, 'прогрев': прогрев, 'измерения': серии,
                'медианы_нс': {режим: int(statistics.median(x['длительность_нс'] for x in серии
                    if x['режим'] == режим)) for _, режим in режимы}}
    with os.fdopen(os.open(аргументы.выход, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644), 'wb') as файл:
        файл.write(хранение.байты(результат)); файл.flush(); os.fsync(файл.fileno())
    print(json.dumps({'медианы_нс': результат['медианы_нс'], 'входы_неизменны': True}, ensure_ascii=False))


if __name__ == '__main__': выполнить()

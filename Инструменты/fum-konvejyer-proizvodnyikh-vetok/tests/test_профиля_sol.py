    def test_версия_не_заменяет_уже_подготовленную_luna(self):
        with новое_поколение() as (_, объект, _, запуск, _, _, _):
            запуск.update(схема="fum.запуск-двух-слоёв.5",
                          профиль_модели={"model": "gpt-6-luna", "thinking": "low"})
            план = объект.предпросмотр(запуск)
            объект.подготовить(запуск, план["sha256"])
            до = объект.хранилище.путь.read_bytes()
            выбрать_sol(запуск)
            with self.assertRaisesRegex(ValueError, "неизменяемый"):
                объект.предпросмотр(запуск)
            self.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_терминал_не_меняет_историю_и_деревья_повтор_не_пишет(self):
        with новое_поколение() as (корень, объект, _, запуск, _, _, прежние):
            выбрать_sol(запуск)
            план = объект.предпросмотр(запуск)
            объект.подготовить(запуск, план["sha256"])
            вход, _, _ = остановить_до_назначения(корень, объект, запуск, план)
            слой = вход["слои"]["события"]
            дети = {**прежние, "новый": (Path(слой["корень"]), слой["задача"], Path(слой["источник"]["путь"]))}
            деревья = снимки(дети)
            до = объект.хранилище.прочитать()
            квитанция = завершение_запуска.предпросмотр(объект, вход)
            self.assertEqual(до, объект.хранилище.прочитать())
            self.assertEqual(квитанция, завершение_запуска.завершить(объект, вход, квитанция["sha256"]))
            после = объект.хранилище.прочитать()
            del после["приёмы"][терминал_запуска.ключ(вход["запуск"])]
            self.assertEqual(до, после)
            байты = объект.хранилище.путь.read_bytes()
            self.assertEqual(квитанция, завершение_запуска.завершить(объект, вход, квитанция["sha256"]))
            self.assertEqual(байты, объект.хранилище.путь.read_bytes())
            self.assertEqual(деревья, снимки(дети))

    def test_терминал_отказывает_при_неверном_фактическом_усилии(self):
        with новое_поколение() as (корень, объект, _, запуск, _, _, _):
            выбрать_sol(запуск)
            план = объект.предпросмотр(запуск)
            объект.подготовить(запуск, план["sha256"])
            вход, _, _ = остановить_до_назначения(корень, объект, запуск, план)
            источник = Path(вход["слои"]["события"]["источник"]["путь"])
            записи = [хранение.разобрать(с) for с in источник.read_bytes().splitlines()]
            записи[1]["payload"]["effort"] = "low"
            источник.write_bytes(b"".join(строка(з) for з in записи))
            вход["слои"]["события"]["источник"] = граница(источник)
            до = объект.хранилище.путь.read_bytes()
            with self.assertRaisesRegex(ValueError, "сохранённым профилем"):
                завершение_запуска.предпросмотр(объект, вход)
            self.assertEqual(до, объект.хранилище.путь.read_bytes())



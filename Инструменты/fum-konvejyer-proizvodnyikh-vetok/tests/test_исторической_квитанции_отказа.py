"""Самосогласованный SHA не превращает неизвестный эффект в принятую доставку."""
import copy
import json
from pathlib import Path
import stat
import unittest

from test_конверта_приёма import входные
import конверт_приёма as конверт
import эпизод_приёма as эпизод
import историческая_квитанция_отказа as отказ

хранение = эпизод.хранение


def образец():
    ф = {'корень': Path('/tmp/получатель'), 'путь': Path('/tmp/фикстура'),
        'send': {'payload': {'item': {'arguments': {}}}}, 'транспорт': {'payload': {}},
        'сохранить': lambda: {'схема': 'открытая-фикстура', 'координатор': {},
            'остановка': {}, 'ожидание': {}, 'возобновление': {}}}
    пакет = {'схема': 'fum.конверт-дочернего-приёма.1', **входные(ф)}
    назначение = {'граница': 'Только чистый разбор; Git и native проверяет вызывающий'}
    блок = конверт.разобрать_текст(пакет['текст'])
    блок['назначение_sha256'] = хранение.хэш(назначение)
    пакет['текст'] = конверт.приём_интеграции.сформировать(блок)
    пакет['sha256'] = хранение.хэш(пакет)
    тело = {'схема': 'fum.основание-дочернего-приёма.1', 'назначение': назначение,
        'поручение': блок, 'эпизод': хранение.хэш({к: блок[к] for к in ('назначение_sha256', 'исполнитель')}),
        'срез': блок['срез'], 'дерево': пакет['план']['источник']['дерево'],
        'приёмка': {'фикстура': True}, 'нативный_приём': {'фикстура': True},
        'журнал': блок['журнал'], 'проверка': блок['проверка'], 'разрешение_записи': False}
    основание = {**тело, 'sha256': хранение.хэш(тело)}
    защищённые = {'локальное.bin': {'режим': stat.S_IFREG | 0o600, 'sha256': '9' * 64}}
    данные = {'схема': 'fum.квитанция-обратной-доставки.2', 'план': блок['план'],
        'корень': блок['корень'], 'ref': блок['ref'], 'владелец': блок['исполнитель'],
        'источник': блок['срез'], 'до': блок['исходный_коммит'], 'стадия': 'эффект не подтверждён',
        'дерево': основание['дерево'], 'защищённые': защищённые, 'проверка': None,
        'коммит': None, 'публикация': None, 'получатель': 'unknown', 'основание': None, 'отчёт': None}
    return пакет, основание, данные, copy.deepcopy(защищённые)


def сырые(данные):
    return хранение.байты({'данные': данные, 'sha256': хранение.хэш(данные)})


class ПроверкаИсторическойКвитанции(unittest.TestCase):
    def test_неизвестный_эффект_сохраняется_без_разрешения_повтора(self):
        п, о, д, з = образец(); до = copy.deepcopy((п, о, д, з))
        результат = отказ.проверить(сырые(д), о, п, з)
        self.assertEqual('unknown', результат['исход_эффекта'])
        self.assertIs(False, результат['повтор_эффекта_разрешён'])
        self.assertEqual(хранение.хэш(д), результат['квитанция_sha256'])
        self.assertEqual(д['источник'], результат['срез'])
        self.assertNotEqual(п['план']['получатели'][0]['дерево'], д['дерево'])
        self.assertEqual(до, (п, о, д, з))

    def test_самосогласованная_чужая_квитанция_отклоняется(self):
        for ключ, значение in {'план': '0' * 64, 'корень': '/tmp/другой',
                'ref': 'refs/heads/codex/other', 'владелец': '44444444-4444-4444-8444-444444444444',
                'до': '7' * 40, 'источник': 'a' * 40, 'дерево': 'f' * 40}.items():
            with self.subTest(ключ=ключ):
                п, о, д, з = образец(); д[ключ] = значение
                with self.assertRaises(ValueError): отказ.проверить(сырые(д), о, п, з)

    def test_поздние_результаты_не_объявляются_наблюдённым_отказом(self):
        for ключ in ('проверка', 'коммит', 'публикация', 'основание', 'отчёт'):
            with self.subTest(ключ=ключ):
                п, о, д, з = образец(); д[ключ] = {'появилось': True}
                with self.assertRaises(ValueError): отказ.проверить(сырые(д), о, п, з)

    def test_подтверждение_или_иная_стадия_не_сводятся_к_unknown(self):
        for ключ, значение in (('получатель', 'подтверждено'), ('стадия', 'закоммичено')):
            with self.subTest(ключ=ключ):
                п, о, д, з = образец(); д[ключ] = значение
                with self.assertRaises(ValueError): отказ.проверить(сырые(д), о, п, з)

    def test_полный_состав_и_схема_строги(self):
        for правка in ({'схема': 'fum.квитанция-обратной-доставки.1'}, {'лишнее': True}):
            п, о, д, з = образец(); д.update(правка)
            with self.assertRaises(ValueError): отказ.проверить(сырые(д), о, п, з)

    def test_неканонические_байты_и_повреждённый_SHA_не_принимаются(self):
        п, о, д, з = образец()
        for raw in (json.dumps({'данные': д, 'sha256': хранение.хэш(д)}, ensure_ascii=False).encode(),
                    хранение.байты({'данные': д, 'sha256': '0' * 64})):
            with self.assertRaises(ValueError): отказ.проверить(raw, о, п, з)

    def test_изменённое_намерение_не_скрывается_новым_хэшем(self):
        for ключ, значение in (('срез', 'a' * 40), ('дерево', 'f' * 40),
                ('журнал', 'Журнал/2026-09-24_12-00-00_MSK_иной/'), ('проверка', '44444444-4444-4444-8444-444444444444')):
            with self.subTest(ключ=ключ):
                п, о, д, з = образец(); о[ключ] = значение
                о['sha256'] = хранение.хэш({к: в for к, в in о.items() if к != 'sha256'})
                with self.assertRaises(ValueError): отказ.проверить(сырые(д), о, п, з)

    def test_новый_protected_файл_не_теряется_при_чистом_HEAD(self):
        п, о, д, з = образец(); з['новое.bin'] = {'режим': stat.S_IFREG | 0o600, 'sha256': '8' * 64}
        with self.assertRaises(ValueError): отказ.проверить(сырые(д), о, п, з)

    def test_другой_числовой_тип_только_в_квитанции_не_скрывается_равенством(self):
        п, о, д, з = образец()
        д['защищённые']['локальное.bin']['режим'] = float(з['локальное.bin']['режим'])
        self.assertEqual(д['защищённые'], з)
        self.assertNotEqual(хранение.байты(д['защищённые']), хранение.байты(з))
        with self.assertRaises(ValueError): отказ.проверить(сырые(д), о, п, з)

    def test_тип_и_путь_protected_данных_проверяются(self):
        for ключ, запись in (('../чужое', {'режим': stat.S_IFREG | 0o600, 'sha256': '9' * 64}),
                ('локальное.bin', {'режим': True, 'sha256': '9' * 64}),
                ('локальное.bin', {'режим': stat.S_IFREG | 0o600, 'sha256': 'не SHA'})):
            with self.subTest(ключ=ключ, запись=запись):
                п, о, д, з = образец(); д['защищённые'] = з = {ключ: запись}
                with self.assertRaises(ValueError): отказ.проверить(сырые(д), о, п, з)


if __name__ == '__main__':
    unittest.main()

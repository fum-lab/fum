ХОД = '22222222-2222-4222-8222-222222222222'
ПРОВЕРКА = '33333333-3333-4333-8333-333333333333'
ЖУРНАЛ = 'Журнал/2026-09-24_12-00-00_MSK_принять-срез/'


@contextmanager
def фикстура():
    координаторы = []
    исходный_корень = Path(__file__).resolve().parents[3]
    def подготовить(координатор):
        координаторы.append(координатор)
        файлы = set(приём.КОД)
        # Частные importlib-модули могут отсутствовать в sys.modules.
        файлы.update(исходный_корень.glob('Инструменты/*/scripts/**/*.py'))
        файлы.update(исходный_корень / 'Инструменты/fum-struktura-papok-zaprosov/шаблоны' / имя
            for имя in ('запрос.md.шаблон', 'отчёт.md.шаблон'))
        файлы.update(Path(м.__file__).resolve() for м in tuple(sys.modules.values())
            if getattr(м, '__file__', None) and Path(м.__file__).suffix == '.py'
            and Path(м.__file__).resolve().is_relative_to(исходный_корень / 'Инструменты'))
        for путь in файлы:
            цель = координатор / путь.relative_to(исходный_корень)
            цель.parent.mkdir(parents=True, exist_ok=True)
            цель.write_bytes(путь.read_bytes())
    with начальная(подготовить_базу=подготовить) as (корень, источник, параметры):
        координатор = координаторы[0]
        готовность = передача.ПроверкаДочернегоКоммита().подготовить_готовность(корень, источник, параметры)
        итог = коммит.создать(готовность, [НОМЕР])
        вершина = итог['коммит']
        основание = дочернее_назначение.прочитать_основание(корень, параметры['исполнитель'], источник)
        хранение.гит(координатор, 'merge', '--no-ff', '-m', 'Принять первый слой', вершина)
        (координатор / 'другой-слой.txt').write_text('Открытый результат второго слоя\n')
        хранение.гит(координатор, 'add', '.')
        хранение.гит(координатор, 'commit', '-qm', 'Объединить слои')
        срез = хранение.гит(координатор, 'rev-parse', 'HEAD').strip()
        свидетельство = (координатор / 'другой-слой.txt').read_bytes()
        решение = {'схема': 'fum.решение-приёмки-среза.1', 'коммит': срез,
            'дерево': хранение.гит(координатор, 'rev-parse', срез + '^{tree}').strip(),
            'проверяющий': ЗАДАЧА, 'состояние': 'принят промежуточный срез',
            'граница': 'Открытая фикстура: сохранён файл результата, реального Desktop нет',
            'свидетельства': [{'путь': 'другой-слой.txt', 'sha256': hashlib.sha256(свидетельство).hexdigest()}]}
        (координатор / 'приёмка.json').write_bytes(хранение.байты(решение))
        хранение.гит(координатор, 'add', 'приёмка.json')
        хранение.гит(координатор, 'commit', '-qm', 'Сохранить приёмку')
        приёмка = хранение.гит(координатор, 'rev-parse', 'HEAD').strip()
        описание = {'корень': str(координатор), 'ref': хранение.гит(координатор, 'symbolic-ref', 'HEAD').strip(),
            'коммит': приёмка, 'владелец': ЗАДАЧА, 'срез': срез,
            'приёмка': {'путь': 'приёмка.json', 'sha256': хранение.хэш(решение)}}
        владельцы = {str(корень): {'задача': параметры['исполнитель'], 'ref': параметры['ветка']}}
        план = доставка_план.построить_план(описание, [str(корень)], владельцы)
        блок = {'схема': 'fum.поручение-дочернего-приёма.1', 'корневая_задача': ЗАДАЧА,
            'исполнитель': параметры['исполнитель'], 'база': параметры['исходный_коммит'],
            'назначение_sha256': хранение.хэш(дочернее_назначение.привязка(основание)),
            'слой': основание['слой'], 'корень': str(корень), 'ref': параметры['ветка'],
            'исходный_коммит': вершина, 'срез': срез, 'источник_приёмки': приёмка,
            'план': план['идентификатор'], 'журнал': ЖУРНАЛ, 'проверка': ПРОВЕРКА}
        папка = корень.parent / 'адресный-приём'; папка.mkdir()
        остановка = папка / 'остановка.jsonl'
        остановка.write_bytes(источник.read_bytes() + b''.join(строка(э) for э in [
            {'type': 'event_msg', 'payload': {'type': 'task_complete', 'turn_id': ХОД}},
            {'type': 'event_msg', 'payload': {'type': 'thread_settings_applied',
                'thread_id': параметры['исполнитель'], 'thread_settings': {'cwd': str(корень)}}}]))
        журнал_координатора = папка / 'координатор.jsonl'
        def отправить(текст):
            ожидание = событие('wait_threads', 'wait', {'targets': [{'threadId': параметры['исполнитель']}], 'timeoutMs': 0}, 10, 20)
            ожидание['payload']['item']['result']['content'] = [{'type': 'text', 'text': json.dumps({'polls': [
                {'thread': {'id': параметры['исполнитель'], 'status': {'type': 'idle'}},
                 'latestTurn': {'id': ХОД, 'status': 'completed', 'error': None}}]})}]
            отправка = событие('send_message_to_thread', 'send', {'threadId': параметры['исполнитель'], 'prompt': текст}, 21, 22)
            журнал_координатора.write_bytes(b''.join(строка(э) for э in [
                {'type': 'session_meta', 'payload': {'id': ЗАДАЧА}}, ожидание, отправка]))
            источник.write_bytes(остановка.read_bytes() + строка({'type': 'response_item', 'payload': {
                'type': 'function_call_output', 'name': 'send_message_to_thread',
                'output': '<codex_delegation>\n  <source_thread_id>' + ЗАДАЧА + '</source_thread_id>\n  <input>'
                    + html.escape(текст, quote=False) + '</input>\n</codex_delegation>'}}))
            return {'схема': 'fum.свидетельство-дочернего-приёма.1',
                'координатор': граница(журнал_координатора, корень=True), 'остановка': граница(остановка),
                'ожидание': 'wait', 'возобновление': 'send'}
        # In-process фикстура исполняет настоящий читатель, но описывает загруженные
        # файлы их точными копиями из C. Холодный запуск из C здесь не доказывается.
        код = {корень / путь.relative_to(исходный_корень): хэш for путь, хэш in приём.КОД.items()}
        with mock.patch.object(приём, 'КОД', код):
            yield {'корень': корень, 'координатор': координатор, 'источник': источник,
                   'задача': параметры['исполнитель'], 'план': план, 'блок': блок, 'отправить': отправить}


def прочитать_холодно(пример, текст, свидетельство):
    """Новый процесс действительно импортирует читатели из копии C получателя."""
    вход = пример['корень'].parent / 'холодный-вход.json'
    вход.write_bytes(хранение.байты({'задача': пример['задача'], 'источник': str(пример['источник']),
        'план': пример['план'], 'свидетельство': свидетельство, 'текст': текст}))
    код = '''from pathlib import Path
import sys,json
корень=Path.cwd()
for имя in ('fum-konvejyer-proizvodnyikh-vetok','fum-reyestr-planirovaniya','fum-svyaznostj-rabochej-sessii'):
    sys.path.insert(0,str(корень/'Инструменты'/имя/'scripts'))
import приём_интеграции
данные=json.loads(Path(sys.argv[1]).read_bytes())
print(json.dumps(приём_интеграции.прочитать(корень,данные['задача'],данные['источник'],данные['план'],данные['свидетельство'],данные['текст']),ensure_ascii=False))
'''
    результат = subprocess.run([sys.executable, '-B', '-c', код, str(вход)], cwd=пример['корень'],
        env={**os.environ, 'CODEX_THREAD_ID': пример['задача']}, capture_output=True, text=True)
    if результат.returncode:
        raise AssertionError(результат.stderr)
    return json.loads(результат.stdout)

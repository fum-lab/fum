корень = Path.cwd()
scripts = корень / 'Инструменты/fum-konvejyer-proizvodnyikh-vetok/scripts'
sys.path.insert(0, str(scripts))
assert 'создание_коммита' not in sys.modules
cli = runpy.run_path(str(scripts / 'подготовить-приём.py'))
import конверт_приёма as конверт
import приватный_вход_приёма as вход
import свежесть_приёма
import доставка_отчёта

эпизод, коммит, хранение = вход.эпизод, вход.коммит, вход.хранение
данные = json.loads(Path(sys.argv[1]).read_bytes())
текст = данные['текст']; блок = конверт.разобрать_текст(текст)
конверт.КОРЕНЬ_СОСТОЯНИЯ = корень.parent / 'частное-получателя'
эпизод.КОРЕНЬ_СОСТОЯНИЯ = корень.parent / 'эпизоды-обнаружения'
коммит.готовность.КОРЕНЬ_СОСТОЯНИЯ = корень.parent / 'готовность-обнаружения'
профиль = []

def измерить(стадия, действие):
    начало = time.monotonic_ns()
    try:
        return действие()
    finally:
        профиль.append({'стадия': стадия, 'наносекунды': time.monotonic_ns() - начало})

def вызвать(*аргументы):
    вывод = io.StringIO()
    with contextlib.redirect_stdout(вывод):
        код = cli['главная'](list(аргументы))
    результат = json.loads(вывод.getvalue())
    assert код == 0, результат
    return результат['результат']

# Native действительно располагается внутри другого Git-предка, как ~/.codex.
родитель = корень.parent / 'native-git'; родитель.mkdir()
subprocess.run(['git', 'init', '-q', str(родитель)], check=True)
источник = родитель / 'native.jsonl'
источник.write_bytes(Path(данные['источник']).read_bytes())
старый_HEAD = коммит.гит(корень, 'rev-parse', 'HEAD')
ожидание = вызвать('ожидать', '--исходник', str(источник), '--предел-секунд', '0')
assert ожидание['состояние'] == 'ожидается-конверт'
assert not конверт.КОРЕНЬ_СОСТОЯНИЯ.exists() and not эпизод.КОРЕНЬ_СОСТОЯНИЯ.exists()
assert not коммит.гит(корень, 'status', '--porcelain')

публикация = {к: данные[к] for к in ('текст', 'план', 'свидетельство', 'владельцы')}
публикация['коммит'] = {'имя_автора': 'FUM Писатель', 'заголовок': 'Принять интеграцию',
    'описание': 'Срез получен из обнаруженного конверта без изменения импорта.'}
файл = корень.parent / 'публикация.json'; хранение.установить(файл, хранение.байты(публикация))

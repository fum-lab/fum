"""Малое реальное Git-слияние; нативный допуск явно заменён синтетическим."""
from contextlib import contextmanager
import copy
import os
from pathlib import Path
import sys
from unittest import mock

ИНСТРУМЕНТЫ = Path(__file__).resolve().parents[2]
for КАТАЛОГ in ('fum-reyestr-planirovaniya/tests', 'fum-konvejyer-proizvodnyikh-vetok/scripts'):
    sys.path.insert(0, str(ИНСТРУМЕНТЫ / КАТАЛОГ))
from test_обратная_доставка import Фикстура, гит, ЗАДАЧА, КООРДИНАТОР
import эпизод_приёма as эпизод
from доставка_план import построить_план, прочитать_приёмку


class ФикстураПриёма(Фикстура):
    def __init__(сам, папка, *, равное_дерево=False):
        сам.папка = Path(папка).resolve()
        сам.источник, сам.цель = сам.папка / 'источник', сам.папка / 'получатель'
        сам.источник.mkdir()
        гит(сам.источник, 'init', '-b', 'codex/источник')
        сам.записать(сам.источник, 'основа.txt', 'основа\n')
        сам.записать(сам.источник, '.gitignore', '*.private\n')
        сам.база = сам.коммит(сам.источник)
        гит(сам.источник, 'worktree', 'add', '-b', 'codex/получатель', str(сам.цель))
        сам.записать(сам.цель, 'работа.txt', 'первый слой\n')
        сам.вершина = сам.коммит(сам.цель)
        гит(сам.источник, 'merge', '--no-ff', '-m', 'Объединить слой', сам.вершина)
        if not равное_дерево:
            сам.записать(сам.источник, 'второй.txt', 'второй слой\n')
            сам.коммит(сам.источник)
        сам.срез = гит(сам.источник, 'rev-parse', 'HEAD')
        сам.описание = сам.принять(сам.срез)
        сам.владельцы = {str(сам.цель): {'задача': ЗАДАЧА, 'ref': 'refs/heads/codex/получатель'}}
        сам.реестр = сам.папка / 'владельцы.json'
        сам.реестр.write_bytes(эпизод.хранение.байты(сам.владельцы))
        сам.план_приёма = построить_план(сам.описание, [str(сам.цель)], сам.владельцы)
        сам.назначение = {'схема': 'открытая-синтетическая-привязка', 'база': сам.база,
            'корневая_задача': КООРДИНАТОР, 'исполнитель': ЗАДАЧА}
        сам.блок = {'схема': 'fum.поручение-дочернего-приёма.1', 'корневая_задача': КООРДИНАТОР,
            'исполнитель': ЗАДАЧА, 'база': сам.база, 'назначение_sha256': эпизод.хранение.хэш(сам.назначение),
            'слой': 'события', 'корень': str(сам.цель), 'ref': 'refs/heads/codex/получатель',
            'исходный_коммит': сам.вершина, 'срез': сам.срез, 'источник_приёмки': сам.описание['коммит'],
            'план': сам.план_приёма['идентификатор'], 'журнал': 'Журнал/2026-09-24_12-00-00_MSK_принять-срез/',
            'проверка': '33333333-3333-4333-8333-333333333333'}
        сам.основание = сам.собрать(сам.блок)

    def собрать(сам, блок):
        тело = {'схема': 'fum.основание-дочернего-приёма.1', 'назначение': сам.назначение,
            'поручение': блок, 'эпизод': эпизод.хранение.хэш({к: блок[к] for к in ('назначение_sha256', 'исполнитель')}),
            'срез': блок['срез'], 'дерево': сам.план_приёма['источник']['дерево'],
            'приёмка': прочитать_приёмку(сам.цель, сам.описание['коммит'], сам.срез, сам.описание['приёмка']),
            'нативный_приём': {'фикстура': 'Без настоящего Desktop'}, 'журнал': блок['журнал'],
            'проверка': блок['проверка'], 'разрешение_записи': False}
        return {**тело, 'sha256': эпизод.хранение.хэш(тело)}

    @contextmanager
    def приём(сам, *, основание=None, план=None, перечитать=None, задача=ЗАДАЧА):
        import слияние_приёма
        прежний = Path.cwd()
        os.chdir(сам.цель)
        try:
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': задача}), \
                    mock.patch.object(эпизод, 'КОРЕНЬ_СОСТОЯНИЯ', сам.папка / 'эпизоды'):
                yield слияние_приёма.СлияниеПриёма(основание or сам.основание,
                    план or сам.план_приёма, сам.реестр,
                    перечитать or (lambda: copy.deepcopy(сам.основание)))
        finally:
            os.chdir(прежний)

    def отпечаток(сам):
        return {str(корень): (гит(корень, 'rev-parse', 'HEAD'), гит(корень, 'write-tree'),
                гит(корень, 'status', '--porcelain')) for корень in (сам.источник, сам.цель)}

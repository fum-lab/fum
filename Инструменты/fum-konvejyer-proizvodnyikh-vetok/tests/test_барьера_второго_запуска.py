"""Допуск .7 не создаёт второго исполнителя до доказанной начальной записи."""
import copy
import importlib
import json
import os
from pathlib import Path
import unittest
from unittest import mock

from фикстура_барьера_запуска import запуск, первый, ПОЛИТИКА
from test_запуска_слоёв import хранение, постановка, строка


class ПроверкаБарьера(unittest.TestCase):
    def отказ_без_попытки(self, объект, пакет, план, источник=None):
        до = объект.хранилище.прочитать()
        with self.assertRaises(хранение.ОшибкаПриёма):
            объект.допустить(пакет, 'сообщения', источник_первого_ребёнка=источник)
        self.assertEqual(до, объект.хранилище.прочитать())
        self.assertNotIn(план['попытки']['сообщения'], до['попытки'])

    def test_нет_первой_попытки_или_наблюдения(self):
        with запуск() as (корень, объект, пакет, план):
            self.отказ_без_попытки(объект, пакет, план)
            _, _, источник, _, _, _ = первый(корень, объект, пакет, план)
            self.отказ_без_попытки(объект, пакет, план, источник)

    def test_асинхронный_ответ_и_раннее_наблюдение_разрешают_один_вызов(self):
        with запуск() as (корень, объект, пакет, план):
            _, _, источник, _, _, _ = первый(корень, объект, пакет, план, писатель=True)
            self.assertEqual(пакет['постановка']['коммит'], хранение.гит(корень,'rev-parse','HEAD').strip())
            второй = объект.допустить(пакет, 'сообщения', источник_первого_ребёнка=источник)
            self.assertTrue(второй['разрешён_вызов'])
            до = объект.хранилище.прочитать()
            повтор = объект.допустить(пакет, 'сообщения')
            self.assertFalse(повтор['разрешён_вызов'])
            self.assertEqual(второй['попытка'], повтор['попытка'])
            self.assertEqual(до, объект.хранилище.прочитать())

    def test_изменённый_префикс_отклонён_даже_после_наблюдения(self):
        with запуск() as (корень, объект, пакет, план):
            _, _, источник, _, записи, _ = первый(корень, объект, пакет, план, писатель=True)
            записи[1]['payload']['approval_policy']='on-request'
            источник.write_bytes(b''.join(строка(з) for з in записи))
            self.отказ_без_попытки(объект, пакет, план, источник)

    def test_неизвестные_права_не_становятся_допуском_из_слов_ребёнка(self):
        with запуск() as (корень, объект, пакет, план):
            политика={**ПОЛИТИКА,'sandbox_policy':{'type':'workspace-write'}}
            _, _, источник, _, записи, _ = первый(корень, объект, пакет, план, политика=политика, писатель=True)
            with источник.open('ab') as f: f.write(строка({'type':'event_msg','payload':{'type':'agent_message','message':'Full Access'}}))
            self.отказ_без_попытки(объект, пакет, план, источник)

    def test_прежняя_версия_не_требует_барьер_и_не_заменяется_под_тем_же_ключом(self):
        with запуск(6) as (корень, объект, пакет, план):
            объект.допустить(пакет,'события')
            self.assertTrue(объект.допустить(пакет,'сообщения')['разрешён_вызов'])
            иной=copy.deepcopy(пакет);иной['схема']='fum.запуск-двух-слоёв.7'
            with self.assertRaises(хранение.ОшибкаПриёма): объект.предпросмотр(иной)

    def test_права_до_записи_повторяются_без_мутаций(self):
        with запуск() as (корень, объект, пакет, план):
            дерево, задача, источник, _, _, _=первый(корень,объект,пакет,план)
            модуль=importlib.import_module('права_запуска')
            до=хранение.гит(дерево,'show-ref')
            with mock.patch.dict(os.environ,{'CODEX_THREAD_ID':задача}):
                результат=модуль.проверить_до_записи(дерево,задача,источник)
                self.assertEqual(результат,модуль.проверить_до_записи(дерево,задача,источник))
            self.assertFalse(результат['разрешение_записи'])
            self.assertEqual(до,хранение.гит(дерево,'show-ref'))
            self.assertFalse(постановка.путь_подтверждения(дерево).exists())
            self.assertFalse(хранение.гит(дерево,'status','--porcelain'))

    def test_политики_с_пропусками_противоречиями_и_null_закрыты(self):
        with запуск() as (корень,объект,пакет,план):
            дерево,задача,источник,_,записи,_=первый(корень,объект,пакет,план)
            модуль=importlib.import_module('права_запуска')
            исходный=copy.deepcopy(записи[1]['payload'])
            варианты=[{'approval_policy':None},{'permission_profile':{'type':'disabled','extra':True}},
                {'active_permission_profile':{'id':':workspace'}},{'file_system_sandbox_policy':None},
                {'sandbox_policy':'danger-full-access'},{'effort':'low'},{'model':'gpt-6-astra'}]
            без=copy.deepcopy(исходный);del без['approvals_reviewer'];варианты.append(без)
            for вариант in варианты:
                with self.subTest(вариант=вариант):
                    записи[1]['payload']=вариант if 'cwd' in вариант else {**исходный,**вариант}
                    источник.write_bytes(b''.join(строка(з) for з in записи))
                    with mock.patch.dict(os.environ,{'CODEX_THREAD_ID':задача}),self.assertRaises(хранение.ОшибкаПриёма):
                        модуль.проверить_до_записи(дерево,задача,источник)
            self.assertFalse(постановка.путь_подтверждения(дерево).exists())

    def test_правильный_блок_с_подменённым_полным_поручением_не_допущен(self):
        with запуск() as (корень,объект,пакет,план):
            дерево,задача,источник,_,записи,_=первый(корень,объект,пакет,план)
            записи[2]['payload']['output']=записи[2]['payload']['output'].replace('Открытая фикстура','Подменённая фикстура')
            источник.write_bytes(b''.join(строка(з) for з in записи))
            with mock.patch.dict(os.environ,{'CODEX_THREAD_ID':задача}),self.assertRaises(хранение.ОшибкаПриёма):
                importlib.import_module('права_запуска').проверить_до_записи(дерево,задача,источник)

    def test_два_независимых_слоя_той_же_цепочки_не_обходят_барьер(self):
        from фикстура_новых_веток import новое_поколение
        from test_профиля_sol import выбрать_sol
        with новое_поколение(зависимости={'события':[],'сообщения':[]}) as (_,объект,_,пакет,_,_,_):
            выбрать_sol(пакет);объект.предпросмотр(пакет)
            пакет['схема']='fum.запуск-двух-слоёв.7';до=объект.хранилище.путь.read_bytes()
            with self.assertRaises(хранение.ОшибкаПриёма): объект.предпросмотр(пакет)
            self.assertEqual(до,объект.хранилище.путь.read_bytes())

    def test_порядок_списка_не_меняет_зависимость_двух_слоёв(self):
        with запуск(обратный_список=True) as (корень,объект,пакет,план):
            self.assertEqual('сообщения',план['описание']['слои'][0]['слой'])
            _,_,источник,_,_,_=первый(корень,объект,пакет,план,писатель=True)
            self.assertTrue(объект.допустить(пакет,'сообщения',источник_первого_ребёнка=источник)['разрешён_вызов'])

    def test_наблюдение_без_сохранённого_ответа_не_разрешает_второй_create(self):
        with запуск() as (корень,объект,пакет,план):
            _,_,источник,_,_,_=первый(корень,объект,пакет,план,писатель=True,сохранить=False)
            self.отказ_без_попытки(объект,пакет,план,источник)

    def test_дочерний_читатель_понимает_оба_точных_текста_Sol(self):
        модуль=importlib.import_module('дочернее_назначение')
        for версия in (6,7):
            with self.subTest(версия=версия),запуск(версия) as (корень,объект,пакет,план):
                дерево,задача,источник,_,_,_=первый(корень,объект,пакет,план,писатель=True)
                with mock.patch.dict(os.environ,{'CODEX_THREAD_ID':задача}):
                    self.assertEqual('события',модуль.прочитать_основание(дерево,задача,источник)['слой'])

    def test_права_и_поручение_не_смешиваются_из_разных_префиксов(self):
        with запуск() as (корень,объект,пакет,план):
            дерево,задача,источник,_,записи,_=первый(корень,объект,пакет,план)
            модуль=importlib.import_module('права_запуска');чтение=модуль.нативное_назначение.прочитать;первый_вызов=True
            def сменить(*аргументы):
                nonlocal первый_вызов
                r=чтение(*аргументы)
                if первый_вызов:
                    первый_вызов=False;записи[1]['payload']['display_state']='изменено'
                    источник.write_bytes(b''.join(строка(з) for з in записи))
                return r
            with mock.patch.dict(os.environ,{'CODEX_THREAD_ID':задача}),mock.patch.object(модуль.нативное_назначение,'прочитать',side_effect=сменить),self.assertRaises(хранение.ОшибкаПриёма):
                модуль.проверить_до_записи(дерево,задача,источник)
            self.assertFalse(постановка.путь_подтверждения(дерево).exists())
            self.assertEqual('HEAD',хранение.гит(дерево,'rev-parse','--symbolic-full-name','HEAD').strip())

    def test_читатель_отклоняет_подменённую_инструкцию_даже_с_ранним_подтверждением(self):
        with запуск() as (корень,объект,пакет,план):
            дерево,задача,источник,_,записи,_=первый(корень,объект,пакет,план)
            записи[2]['payload']['output']=записи[2]['payload']['output'].replace('До создания ref','После создания ref')
            источник.write_bytes(b''.join(строка(з) for з in записи))
            ref=next(с['ветка'] for с in план['описание']['слои'] if с['слой']=='события')
            хранение.гит(дерево,'switch','-c',ref.removeprefix('refs/heads/'))
            постановка.подтвердить_начало(дерево,задача,пакет['постановка']['коммит'],источник,с_поручением=True)
            with mock.patch.dict(os.environ,{'CODEX_THREAD_ID':задача}),self.assertRaises(хранение.ОшибкаПриёма):
                importlib.import_module('дочернее_назначение').прочитать_основание(дерево,задача,источник)



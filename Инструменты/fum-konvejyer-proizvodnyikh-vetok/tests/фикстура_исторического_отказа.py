"""Настоящие Git-объекты и приватные файлы; native-допуск здесь синтетический."""
import hashlib
from unittest import mock

from фикстура_слияния_приёма import ФикстураПриёма, гит
import конверт_приёма as конверт
import эпизод_приёма as эпизод
import вход_приёма

хранение = эпизод.хранение


class ФикстураИсторическогоОтказа(ФикстураПриёма):
    def __init__(сам, папка, *, подменённое_дерево=False):
        super().__init__(папка)
        if подменённое_дерево:
            # Все внешние хэши согласованы, но источник не соответствует Git-приёмке.
            сам.план_приёма['источник']['дерево'] = гит(сам.цель, 'rev-parse', сам.вершина + '^{tree}')
            сам.план_приёма['идентификатор'] = хранение.хэш({к: з for к, з in сам.план_приёма.items()
                if к != 'идентификатор'})
            сам.блок['план'] = сам.план_приёма['идентификатор']
            сам.основание = сам.собрать(сам.блок)
        сам.приватное = сам.папка / 'приватное'
        сам.приватное.mkdir(mode=0o700)
        сам.текст = конверт.приём_интеграции.сформировать(сам.блок)
        данные = {'схема': 'fum.конверт-дочернего-приёма.1', 'текст': сам.текст,
            'план': сам.план_приёма, 'владельцы': сам.владельцы,
            'свидетельство': {'схема': 'Синтетический native; только FS/Git',
                'координатор': {}, 'остановка': {}, 'ожидание': {}, 'возобновление': {}},
            'коммит': {'имя_автора': 'FUM Писатель', 'заголовок': 'Принять срез',
                'описание': 'Открытая файловая фикстура'}}
        сам.пакет = {**данные, 'sha256': хранение.хэш(данные)}
        with mock.patch.object(конверт, 'КОРЕНЬ_СОСТОЯНИЯ', сам.приватное), \
                mock.patch.object(эпизод, 'КОРЕНЬ_СОСТОЯНИЯ', сам.приватное / 'эпизоды'):
            сам.конверт = конверт.адрес(сам.текст) / 'конверт.json'
            сам.намерение = эпизод.путь_эпизода(сам.основание)
            сам.записать_приватно(сам.конверт, сам.пакет)
            сам.записать_приватно(сам.конверт.with_name('готово.json'),
                {'схема': 'fum.готовый-конверт-приёма.1', 'sha256': хранение.хэш(сам.пакет)})
            сам.сохранить_намерение(сам.основание)
            сам.доставка = сам.намерение.with_suffix('.доставка')
            сам.квитанция = сам.доставка / ('квитанция-' + сам.блок['план'] + '.json')
            сам.записать_приватно(сам.доставка / 'получатель.json',
                {'корень': str(сам.цель), 'начато': True})
            сам.записать_приватно(сам.доставка / 'активная.json', {'идентификатор': сам.блок['план']})
            сам.записать_приватно(сам.доставка / 'замок', b'')
            д = {'схема': 'fum.квитанция-обратной-доставки.2', 'план': сам.блок['план'],
                'корень': str(сам.цель), 'ref': сам.блок['ref'], 'владелец': сам.блок['исполнитель'],
                'источник': сам.срез, 'до': сам.вершина, 'стадия': 'эффект не подтверждён',
                'дерево': сам.основание['дерево'], 'защищённые': {}, 'проверка': None,
                'коммит': None, 'публикация': None, 'получатель': 'unknown', 'основание': None, 'отчёт': None}
            сам.записать_приватно(сам.квитанция, {'данные': д, 'sha256': хранение.хэш(д)})
            сам.вход_пакета = конверт.адрес(сам.текст, получатель=True)
            сам.нативный = str(сам.вход_пакета / 'нативный/источник.jsonl')
            сам.реестр_пакета = сам.вход_пакета / 'владельцы.json'
            сам.записать_приватно(сам.реестр_пакета, сам.владельцы)
            вход = {'схема': 'fum.вход-дочернего-приёма.1', 'источник': сам.нативный,
                'текст': сам.текст, 'план': сам.план_приёма, 'свидетельство': сам.пакет['свидетельство'],
                'реестр': str(сам.реестр_пакета), 'коммит': сам.пакет['коммит']}
            сам.записать_приватно(сам.вход_пакета / 'вход.json', вход)
            сам.параметры = вход_приёма.параметры(вход, сам.основание)
            сам.вход_коммита = сам.намерение.with_suffix('.вход-коммита.json')
            сам.записать_приватно(сам.вход_коммита, сам.параметры)
        сам.описание_чтения = {'конверт': {'путь': str(сам.конверт), 'sha256': сам.sha(сам.конверт)},
            'намерение_sha256': сам.sha(сам.намерение), 'доставка_sha256': сам.sha(сам.квитанция)}

    def записать_приватно(сам, путь, значение):
        хранение.создать_каталоги(путь.parent, сам.приватное, права=0o700)
        путь.write_bytes(значение if type(значение) is bytes else хранение.байты(значение))
        путь.chmod(0o600)

    def сохранить_намерение(сам, основание):
        д = {'схема': 'fum.намерение-дочернего-приёма.1', 'эпизод': основание['эпизод'],
            'основание': основание, 'разрешение_записи': False}
        сам.записать_приватно(сам.намерение, {'данные': д, 'sha256': хранение.хэш(д)})
        сам.записать_приватно(сам.намерение.with_suffix('.начато.json'),
            {'схема': 'fum.начатый-эпизод-приёма.1', 'эпизод': основание['эпизод'],
                'основание_sha256': основание['sha256']})

    @staticmethod
    def sha(путь):
        return hashlib.sha256(путь.read_bytes()).hexdigest()

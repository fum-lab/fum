"""Два настоящих вызова и чистые detached-деревья без назначения писателя."""
from contextlib import contextmanager
import html
import json
from pathlib import Path

from test_области_писателя import область_фикстура
from test_завершения_запуска import граница, вызов
from test_запуска_слоёв import ЗАДАЧА, хранение, строка


def транспорт(текст):
    return '<codex_delegation>\n  <source_thread_id>' + ЗАДАЧА + '</source_thread_id>\n  <input>' + html.escape(текст, quote=False) + '</input>\n</codex_delegation>'


def первичный_вызов(имя, номер, аргументы, ответ, время):
    запись = вызов(имя, номер, аргументы, ответ)
    запись['payload'].update(started_at_ms=время, completed_at_ms=время + 1)
    return запись


def обновить_источники(вход, события):
    путь = Path(вход['источник']['путь'])
    путь.write_bytes(b''.join(строка(с) for с in события))
    вход['источник'] = граница(путь, корень=True)
    for слой in вход['слои'].values():
        слой['источник'] = граница(Path(слой['источник']['путь']))


@contextmanager
def исходный_запуск(сол):
    if сол:
        from фикстура_новых_веток import новое_поколение
        from test_профиля_sol import выбрать_sol
        with новое_поколение() as (корень, объект, _, пакет, _, _, _):
            выбрать_sol(пакет)
            план = объект.предпросмотр(пакет); объект.подготовить(пакет, план['sha256'])
            yield корень, объект, пакет, план
    else:
        with область_фикстура(v2=True, наблюдать=False) as (корень, объект, пакет, план, _, _):
            yield корень, объект, пакет, план


@contextmanager
def два_до_записи(возобновить=True, *, сол=False):
    with исходный_запуск(сол) as (корень, объект, пакет, план):
        база = пакет['постановка']['коммит']
        события = [{'type': 'session_meta', 'payload': {'id': ЗАДАЧА}}]
        слои, ожидания, дети, ходы = {}, {}, {}, {}
        for номер, имя in enumerate(('события', 'сообщения'), 1):
            допуск = объект.допустить(пакет, имя)
            задача = f'00000000-0000-4000-8000-{номер:012d}'
            ход = f'00000000-0000-4000-8001-{номер:012d}'
            дерево = корень.parent / ('до-записи-' + имя)
            хранение.гит(корень, 'worktree', 'add', '--detach', str(дерево), база)
            ответ = {'content': [{'type': 'text', 'text': json.dumps({'clientThreadId': 'ожидание-' + имя})}], 'isError': False}
            объект.сохранить(план['запуск'], имя, допуск['попытка'], ответ)
            события.append(первичный_вызов('create_thread', 'создать-' + имя, допуск['аргументы'], ответ, номер * 10))
            источник = корень.parent / (имя + '.jsonl')
            контекст = {'cwd': str(дерево), 'model': допуск['аргументы']['model'], 'effort': допуск['аргументы']['thinking']}
            записи = [
                {'type': 'session_meta', 'payload': {'id': задача, 'cwd': str(дерево), 'git': {'commit_hash': база}}},
                {'type': 'turn_context', 'payload': контекст},
                {'type': 'response_item', 'payload': {'type': 'function_call_output', 'name': 'create_thread', 'output': транспорт(допуск['аргументы']['prompt'])}},
                {'type': 'event_msg', 'payload': {'type': 'task_complete', 'turn_id': ход, 'last_agent_message': 'Запись прекращена.', 'started_at': 1, 'completed_at': 2, 'duration_ms': 1000, 'time_to_first_token_ms': 1}},
            ]
            источник.write_bytes(b''.join(строка(з) for з in записи))
            слои[имя] = {'вид': 'остановлен-до-записи', 'попытка': допуск['попытка'], 'задача': задача, 'корень': str(дерево), 'источник': граница(источник)}
            дети[имя], ходы[имя] = (дерево, задача, источник), ход
        возобновления = {}
        if возобновить:
            дерево, задача, источник = дети['события']
            модель, усилие = ('gpt-6-sol', 'ultra') if сол else ('gpt-6-astra', 'low')
            аргументы = {'threadId': задача, 'hostId': 'local', 'prompt': 'Продолжи прежнее поручение; сохрани препятствие.', 'model': модель, 'thinking': усилие}
            ответ = {'content': [{'type': 'text', 'text': json.dumps({'threadId': задача})}], 'isError': False}
            события.append(первичный_вызов('send_message_to_thread', 'возобновить-события', аргументы, ответ, 30))
            возобновления['возобновить-события'] = {'слой': 'события', 'аргументы_sha256': хранение.хэш(аргументы), 'ответ_sha256': хранение.хэш(ответ)}
            ходы['события'] = '00000000-0000-4000-8002-000000000001'
            with источник.open('ab') as поток:
                for з in [
                    {'type': 'event_msg', 'payload': {'type': 'task_started', 'turn_id': ходы['события']}},
                    {'type': 'turn_context', 'payload': {'cwd': str(дерево), 'model': модель, 'effort': усилие}},
                    {'type': 'response_item', 'payload': {'type': 'function_call_output', 'name': 'send_message_to_thread', 'output': транспорт(аргументы['prompt'])}},
                    {'type': 'event_msg', 'payload': {'type': 'task_complete', 'turn_id': ходы['события'], 'last_agent_message': 'Передача не выполнена.', 'started_at': 3, 'completed_at': 4, 'duration_ms': 1000, 'time_to_first_token_ms': 1}},
                ]:
                    поток.write(строка(з))
        for номер, имя in enumerate(('сообщения', 'события')):
            задача = дети[имя][1]
            ответ = {'content': [{'type': 'text', 'text': json.dumps({'polls': [{'thread': {'id': задача, 'status': {'type': 'idle'}}, 'latestTurn': {'id': ходы[имя], 'status': 'completed', 'error': None}}]})}], 'isError': False}
            идентификатор = 'ожидать-' + имя
            события.append(первичный_вызов('wait_threads', идентификатор, {'targets': [{'threadId': задача}]}, ответ, 40 + номер * 2))
            ожидания[задача] = идентификатор
        хранение.гит(корень, 'commit', '--allow-empty', '-qm', 'Открытая фикстура исправленного координатора')
        источник = корень.parent / 'родитель-два.jsonl'
        источник.touch()
        вход = {'схема': 'fum.завершение-неудачного-запуска.5', 'запуск': план['запуск'], 'план_sha256': план['sha256'],
            'координатор': объект.хранилище._наблюдать_владельца(), 'источник': {'путь': str(источник)}, 'ожидания': ожидания,
            'слои': слои, 'возобновления': возобновления, 'свидетельство_координатора': {'задача': ЗАДАЧА, 'единственный_координатор': True, 'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}}
        обновить_источники(вход, события)
        yield корень, объект, план, вход, события, дети

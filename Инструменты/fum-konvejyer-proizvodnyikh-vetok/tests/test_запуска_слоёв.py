@contextmanager
def фикстура():
    with открытый_вход() as (корень, источник, решение):
        план = {
            "схема": "fum.план-запуска-двух-слоёв.1",
            "конвейер": "открытый-пилот",
            "шаг": "FUM-STEP-0233",
            "слои": [
                {"слой": "события", "каталог": "Память/события/", "роль": "Собирать события",
                 "ветка": сформировать_ref_ветки("Память/события/", "codex"),
                 "зависит_от": [], "поручение": "Планирование/пилот/события.md"},
                {"слой": "сообщения", "каталог": "Память/сообщения/", "роль": "Выделять сообщения",
                 "ветка": сформировать_ref_ветки("Память/сообщения/", "codex"),
                 "зависит_от": ["события"], "поручение": "Планирование/пилот/сообщения.md"},
            ],
        }
        файлы = {"Планирование/пилот/план.json": хранение.байты(план)}
        файлы.update({слой["поручение"]: ("# " + слой["роль"] + "\n\nОткрытая фикстура, без внешних действий.\n").encode() for слой in план["слои"]})
        for имя, данные in файлы.items():
            путь = корень / имя
            путь.parent.mkdir(parents=True, exist_ok=True)
            путь.write_bytes(данные)
        хранение.гит(корень, "add", ".")
        хранение.гит(корень, "commit", "-qm", "Постановка двух слоёв")
        пакет = {
            "схема": "fum.запуск-двух-слоёв.1", "задача": ЗАДАЧА,
            "постановка": {"коммит": хранение.гит(корень, "rev-parse", "HEAD").strip(),
                           "ветка": хранение.гит(корень, "symbolic-ref", "HEAD").strip(),
                           "файлы": {имя: hashlib.sha256(данные).hexdigest() for имя, данные in файлы.items()}},
            "план": "Планирование/пилот/план.json", "проект": "открытый-проект",
            "источник": str(источник), "решение": решение,
        }
        # Фикстура использует настоящий Git и первичный JSONL. Совпадение
        # checkout исполняемого кода проверяет отдельный прежний допуск.
        with mock.patch.object(приём, "проверить_инструменты"):
            yield корень, пакет, план


def исполнитель(корень):
    return importlib.import_module("запуск_слоёв").ИсполнительЗапускаСлоёв(корень, ЗАДАЧА)


def подготовить(корень, пакет):
    объект = исполнитель(корень)
    план = объект.предпросмотр(пакет)
    объект.подготовить(пакет, план["sha256"])
    return объект, план


def ребёнок(корень, пакет, слой, допуск, номер):
    дерево = корень.parent / ("дерево-" + str(номер))
    задача = f"00000000-0000-0000-0000-{номер:012d}"
    коммит = пакет["постановка"]["коммит"]
    хранение.гит(корень, "worktree", "add", "-b", слой["ветка"].removeprefix("refs/heads/"), str(дерево), коммит)
    источник = корень.parent / ("задача-" + str(номер) + ".jsonl")
    поручение = "<codex_delegation>\n  <source_thread_id>" + ЗАДАЧА + "</source_thread_id>\n  <input>" + допуск["аргументы"]["prompt"] + "</input>\n</codex_delegation>"
    источник.write_bytes(
        строка({"type": "session_meta", "payload": {"id": задача, "cwd": str(дерево), "git": {"commit_hash": коммит}}})
        + строка({"type": "turn_context", "payload": {"cwd": str(дерево), "model": "gpt-6-astra", "effort": "low"}})
        + строка({"type": "response_item", "payload": {"type": "function_call_output", "name": "create_thread", "output": поручение}})
    )
    постановка.подтвердить_начало(дерево, задача, коммит, источник,
                               с_поручением=пакет["схема"] == "fum.запуск-двух-слоёв.2")
    return дерево, задача, источник


class ПроверкаЗапускаСлоёв(unittest.TestCase):
    def test_предпросмотр_двух_слоёв_одного_шага_не_придумывает_размещение(self):
        with фикстура() as (корень, пакет, _):
            объект = исполнитель(корень)
            до = хранение.гит(корень, "status", "--porcelain")
            план = объект.предпросмотр(пакет)
            self.assertEqual(2, len(set(план["попытки"].values())))
            self.assertEqual({"события": None, "сообщения": None}, план["наблюдения"])
            self.assertEqual("refs/heads/codex/приём", план["координатор"]["ref"])
            self.assertFalse(объект.хранилище.каталог.exists())
            self.assertEqual(до, хранение.гит(корень, "status", "--porcelain"))

    def test_неверный_коммит_или_хэш_не_оставляют_попытку(self):
        with фикстура() as (корень, пакет, _):
            объект = исполнитель(корень)
            for поле, значение in (("коммит", "0" * 40), ("файлы", {пакет["план"]: "0" * 64})):
                иной = copy.deepcopy(пакет)
                иной["постановка"][поле] = значение
                with self.assertRaises(хранение.ОшибкаПриёма):
                    объект.предпросмотр(иной)
                self.assertFalse(объект.хранилище.каталог.exists())

    def test_пересечение_каталогов_и_повтор_слоя_отклоняются(self):
        with фикстура() as (_, _, план):
            модуль = importlib.import_module("план_запуска_слоёв")
            for изменение in ({"слой": "события"}, {"каталог": "Память/события/вложенный/"}, {"ветка": "refs/heads/master"}, {"зависит_от": ["сообщения"]}):
                иной = copy.deepcopy(план)
                иной["слои"][1].update(изменение)
                with self.assertRaises(ValueError):
                    модуль.проверить_план(иной)

    def test_потеря_ответа_и_новый_исполнитель_не_создают_второй_вызов(self):
        with фикстура() as (корень, пакет, _):
            объект, _ = подготовить(корень, пакет)
            первый = объект.допустить(пакет, "события")
            self.assertTrue(первый["разрешён_вызов"])
            повтор = исполнитель(корень).допустить(пакет, "события")
            self.assertFalse(повтор["разрешён_вызов"])
            self.assertEqual(первый["попытка"], повтор["попытка"])
            self.assertTrue(объект.допустить(пакет, "сообщения")["разрешён_вызов"])

    def test_новый_коммит_не_сбрасывает_прежний_ключ_запуска(self):
        with фикстура() as (корень, пакет, _):
            объект, план = подготовить(корень, пакет)
            первая = объект.допустить(пакет, "события")
            (корень / "добавление.md").write_text("Новая граница\n")
            хранение.гит(корень, "add", ".")
            хранение.гит(корень, "commit", "-qm", "Поздний коммит")
            иной = copy.deepcopy(пакет)
            иной["постановка"]["коммит"] = хранение.гит(корень, "rev-parse", "HEAD").strip()
            with self.assertRaises(хранение.ОшибкаПриёма):
                объект.предпросмотр(иной)
            состояние = объект.состояние(план["запуск"])
            self.assertEqual(первая["попытка"], состояние["попытки"]["события"]["попытка"])

    def test_client_id_сохраняет_ожидание_и_сырой_ответ(self):
        with фикстура() as (корень, пакет, _):
            объект, план = подготовить(корень, пакет)
            допуск = объект.допустить(пакет, "события")
            ответ = {"content": [{"type": "text", "text": json.dumps({"clientThreadId": "ожидание"})}]}
            объект.сохранить(план["запуск"], "события", допуск["попытка"], ответ)
            состояние = объект.состояние(план["запуск"])
            self.assertIsNone(состояние["наблюдения"]["события"])
            self.assertIn("ожидание", json.dumps(состояние, ensure_ascii=False))
            with self.assertRaises(хранение.ОшибкаПриёма):
                объект.сохранить(план["запуск"], "события", допуск["попытка"], {"threadId": "другой"})

    def test_наблюдение_связывает_реальную_задачу_с_нужным_слоем(self):
        with фикстура() as (корень, пакет, описание):
            объект, план = подготовить(корень, пакет)
            допуск = объект.допустить(пакет, "события")
            дерево, задача, источник = ребёнок(корень, пакет, описание["слои"][0], допуск, 1)
            результат = объект.наблюдать(план["запуск"], "события", дерево, задача, источник)
            self.assertEqual(задача, результат["задача"])
            self.assertEqual(str(дерево), результат["корень"])
            self.assertEqual(результат, объект.наблюдать(план["запуск"], "события", дерево, задача, источник))
            объект.допустить(пакет, "сообщения")
            with self.assertRaises(хранение.ОшибкаПриёма):
                объект.наблюдать(план["запуск"], "сообщения", дерево, задача, источник)

    def test_проект_не_подменяет_подтверждённое_решение(self):
        with фикстура() as (корень, пакет, _):
            пакет["проект"] = "чужой-проект"
            with self.assertRaises(хранение.ОшибкаПриёма):
                исполнитель(корень).предпросмотр(пакет)

    def test_поздний_чужой_ответ_не_противоречит_сохранённому_наблюдению(self):
        with фикстура() as (корень, пакет, описание):
            объект, план = подготовить(корень, пакет)
            допуск = объект.допустить(пакет, "события")
            дерево, задача, источник = ребёнок(корень, пакет, описание["слои"][0], допуск, 1)
            объект.наблюдать(план["запуск"], "события", дерево, задача, источник)
            до = объект.хранилище.путь.read_bytes()
            with self.assertRaises(хранение.ОшибкаПриёма):
                объект.сохранить(план["запуск"], "события", допуск["попытка"], {"threadId": "00000000-0000-0000-0000-000000000999"})
            self.assertEqual(до, объект.хранилище.путь.read_bytes())
            объект.сохранить(план["запуск"], "события", допуск["попытка"], {"threadId": задача})

    def test_занятый_ref_останавливает_первый_вызов(self):
        with фикстура() as (корень, пакет, описание):
            объект, план = подготовить(корень, пакет)
            хранение.гит(корень, "branch", описание["слои"][0]["ветка"].removeprefix("refs/heads/"))
            with self.assertRaises(хранение.ОшибкаПриёма):
                объект.допустить(пакет, "события")
            self.assertIsNone(объект.состояние(план["запуск"])["попытки"]["события"])

    def test_недопустимый_git_ref_не_доходит_до_попытки(self):
        with фикстура() as (корень, пакет, описание):
            описание["слои"][0]["каталог"] = "Память/данные.lock/"
            описание["слои"][0]["ветка"] = сформировать_ref_ветки("Память/данные.lock/", "codex")
            данные = хранение.байты(описание)
            (корень / пакет["план"]).write_bytes(данные)
            хранение.гит(корень, "add", ".")
            хранение.гит(корень, "commit", "-qm", "Неверная ветка в постановке")
            пакет["постановка"]["коммит"] = хранение.гит(корень, "rev-parse", "HEAD").strip()
            пакет["постановка"]["файлы"][пакет["план"]] = hashlib.sha256(данные).hexdigest()
            объект = исполнитель(корень)
            with self.assertRaises(хранение.ОшибкаПриёма):
                объект.предпросмотр(пакет)
            self.assertFalse(объект.хранилище.каталог.exists())



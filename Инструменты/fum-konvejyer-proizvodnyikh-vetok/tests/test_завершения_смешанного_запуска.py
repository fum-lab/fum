"""Один сохранённый писатель и один невызванный допуск завершаются вместе."""
from contextlib import contextmanager
import importlib
import json
import unittest

from фикстура_остановленного_поколения import область_фикстура, подготовить_остановку
from test_завершения_запуска import граница, строка, хранение
from test_интервалов_нативных_вызовов import событие
import терминал_запуска


@contextmanager
def смешанный_запуск():
    with область_фикстура(v2=True) as (корень, объект, запуск, план, назначение, дети):
        объект.допустить(запуск, 'сообщения')
        вход, события = подготовить_остановку(корень, объект, запуск, план, назначение, дети)
        вход['схема'] = 'fum.завершение-неудачного-запуска.4'
        попытка = объект.хранилище.прочитать()['попытки'][план['попытки']['сообщения']]
        вход['слои']['сообщения'] = {'вид': 'не-вызван', 'попытка': попытка['попытка']}
        yield корень, объект, запуск, план, вход, дети, попытка


class ПроверкаСмешанногоЗавершения(unittest.TestCase):
    def setUp(сам):
        сам.модуль = importlib.import_module('завершение_смешанного_запуска')

    def test_единый_терминал_повтор_и_запрет_позднего_допуска(сам):
        with смешанный_запуск() as (_, объект, запуск, план, вход, _, _):
            итог = сам.модуль.предпросмотр(объект, вход)
            сам.assertEqual(итог['слои']['сообщения']['вид'], 'допуск-отозван')
            сам.assertFalse(итог['отсутствие_незаписанного_вызова_доказано'])
            сам.assertEqual(итог, сам.модуль.завершить(объект, вход, итог['sha256']))
            до = объект.хранилище.путь.read_bytes()
            сам.assertEqual(итог, сам.модуль.завершить(объект, вход, итог['sha256']))
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())
            сам.assertEqual(итог, терминал_запуска.прочитать(объект.хранилище.прочитать(), план['запуск']))
            for слой in вход['слои']:
                with сам.assertRaises(ValueError): объект.допустить(запуск, слой)

    def test_вызов_или_ответ_второго_отклоняется(сам):
        for вариант in ('вызов', 'ответ'):
            with сам.subTest(вариант=вариант), смешанный_запуск() as (корень, объект, _, план, вход, _, попытка):
                if вариант == 'ответ':
                    with объект.хранилище.изменить() as состояние:
                        состояние['попытки'][план['попытки']['сообщения']]['ответ'] = {'threadId': 'другой'}
                else:
                    from pathlib import Path
                    путь = Path(вход['источник']['путь'])
                    вызов = событие('create_thread', 'второй', попытка['аргументы'], 20, 21)
                    вызов['payload']['item']['result'] = {'content': [{'type': 'text', 'text': json.dumps({'clientThreadId': 'pending'})}], 'isError': False}
                    with путь.open('ab') as файл: файл.write(строка(вызов))
                    вход['источник'] = граница(путь, корень=True)
                with сам.assertRaises(ValueError): сам.модуль.предпросмотр(объект, вход)

    def test_чужой_путь_или_поздний_индекс_первого_отклоняется(сам):
        for вариант in ('чужой', 'индекс'):
            with сам.subTest(вариант=вариант), смешанный_запуск() as (_, объект, _, _, вход, дети, _):
                просмотр = сам.модуль.предпросмотр(объект, вход)
                дерево = дети['события'][0]
                if вариант == 'чужой': (дерево / 'общий.txt').write_text('Изменение чужой области')
                else: хранение.гит(дерево, 'add', '--', 'Память/события/поток.jsonl')
                with сам.assertRaises(ValueError): сам.модуль.завершить(объект, вход, просмотр['sha256'])
                сам.assertIsNone(терминал_запуска.прочитать(объект.хранилище.прочитать(), вход['запуск']))

    def test_существующая_ветка_второго_не_считается_невызванной(сам):
        with смешанный_запуск() as (корень, объект, запуск, план, вход, _, _):
            ветка = next(с['ветка'] for с in план['описание']['слои'] if с['слой'] == 'сообщения')
            хранение.гит(корень, 'update-ref', ветка, запуск['постановка']['коммит'])
            with сам.assertRaises(ValueError): сам.модуль.предпросмотр(объект, вход)

    def test_позднее_возобновление_первого_отклоняется(сам):
        from pathlib import Path
        with смешанный_запуск() as (_, объект, _, _, вход, дети, _):
            путь = Path(вход['источник']['путь'])
            вызов = событие('send_message_to_thread', 'поздно', {'threadId': дети['события'][1], 'prompt': 'Продолжай'}, 20, 21)
            with путь.open('ab') as файл: файл.write(строка(вызов))
            вход['источник'] = граница(путь, корень=True)
            with сам.assertRaises(ValueError): сам.модуль.предпросмотр(объект, вход)

    def test_поздний_сдвиг_источника_под_замком_отклоняется(сам):
        from pathlib import Path
        from unittest.mock import patch
        with смешанный_запуск() as (_, объект, _, _, вход, дети, _):
            просмотр = сам.модуль.предпросмотр(объект, вход)
            исходный = сам.модуль._план
            def сдвинуть(*аргументы):
                итог = исходный(*аргументы)
                вызов = событие('send_message_to_thread', 'во-время-завершения',
                    {'threadId': дети['события'][1], 'prompt': 'Продолжай'}, 20, 21)
                with Path(вход['источник']['путь']).open('ab') as файл: файл.write(строка(вызов))
                return итог
            до = объект.хранилище.путь.read_bytes()
            with patch.object(сам.модуль, '_план', side_effect=сдвинуть):
                with сам.assertRaisesRegex(ValueError, 'источник'):
                    сам.модуль.завершить(объект, вход, просмотр['sha256'])
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())


if __name__ == '__main__':
    unittest.main()

"""Восстановление известного удаления не меняет остальные байты документа."""
import hashlib
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
import восстановление_поручения as восстановление


МЕТКА = ('\n<!-- FUM-MD-RECENCY:BEGIN -->\n'
         '<!-- last-content-edit: 2026-09-22 12:00:00 MSK -->\n'
         '<!-- content-sha256: sha256:' + 'a' * 64 + ' -->\n'
         '<!-- FUM-MD-RECENCY:END -->\n')
ПОРУЧЕНИЕ = ('Поручение: ёж и 🙂.  \n' + МЕТКА + '\nСохранить всё.\n').encode()
НАЧАЛО = '# Запрос — ё\n\n## Текст запроса\n\n````text\n'.encode()
КОНЕЦ = ('\n````\n\n## Идентификатор сеанса Codex\n\nСобственные данные.  \n' + МЕТКА).encode()


def документ(поручение=ПОРУЧЕНИЕ):
    return НАЧАЛО + поручение + КОНЕЦ


class ПроверкаВосстановленияПоручения(unittest.TestCase):
    def test_известное_удаление_восстанавливается_побайтно(сам):
        повреждённое = документ(ПОРУЧЕНИЕ.replace(МЕТКА.encode(), b'', 1))
        результат, свидетельство = восстановление.предложить(повреждённое, ПОРУЧЕНИЕ)
        сам.assertEqual(результат, документ())
        сам.assertFalse(свидетельство['разрешение_записи'])
        сам.assertFalse(свидетельство['повтор'])
        сам.assertEqual(свидетельство['до_sha256'], hashlib.sha256(повреждённое).hexdigest())
        сам.assertEqual(свидетельство['после_sha256'], hashlib.sha256(документ()).hexdigest())
        начало = len(НАЧАЛО) + ПОРУЧЕНИЕ.index(МЕТКА.encode())
        сам.assertEqual(свидетельство['вставка']['начало'], начало)
        сам.assertEqual(свидетельство['вставка']['байтов'], len(МЕТКА.encode()))
        сам.assertEqual(свидетельство['вставка']['переводов_строки'], МЕТКА.count('\n'))
        сам.assertEqual(результат[:начало], повреждённое[:начало])
        сам.assertEqual(результат[начало + len(МЕТКА.encode()):], повреждённое[начало:])

    def test_целый_оригинал_повторяется_без_изменений(сам):
        результат, свидетельство = восстановление.предложить(документ(), ПОРУЧЕНИЕ)
        сам.assertEqual(результат, документ())
        сам.assertTrue(свидетельство['повтор'])
        сам.assertIsNone(свидетельство['вставка'])

    def test_неизвестное_изменение_поручения_отклоняется(сам):
        повреждённое = документ(ПОРУЧЕНИЕ.replace(МЕТКА.encode(), b'', 1)).replace('Сохранить'.encode(), 'Удалить'.encode())
        with сам.assertRaisesRegex(ValueError, 'известному удалению'):
            восстановление.предложить(повреждённое, ПОРУЧЕНИЕ)

    def test_неоднозначное_поле_отклоняется(сам):
        with сам.assertRaisesRegex(ValueError, 'единственное'):
            восстановление.предложить(документ() + документ(), ПОРУЧЕНИЕ)

    def test_повторный_заголовок_без_пустой_строки_отклоняется(сам):
        for заголовок in ('## Текст запроса\n', '## Текст запроса  \n'):
            with сам.subTest(заголовок=заголовок):
                with сам.assertRaisesRegex(ValueError, 'единственное'):
                    восстановление.предложить(документ() + (заголовок + 'Другой текст\n').encode(), ПОРУЧЕНИЕ)

    def test_поле_внутри_цитаты_не_принимается(сам):
        with сам.assertRaisesRegex(ValueError, 'единственное'):
            восстановление.предложить(b'`````text\n' + документ() + b'`````\n', ПОРУЧЕНИЕ)

    def test_неподдержанные_байты_и_границы_отклоняются(сам):
        for текст, поручение in [(документ().replace(b'\n', b'\r\n'), ПОРУЧЕНИЕ),
                                 (документ(), ПОРУЧЕНИЕ + b'\xff'),
                                 (документ()[:-1], ПОРУЧЕНИЕ),
                                 (документ(), ПОРУЧЕНИЕ[:-1])]:
            with сам.subTest(текст=текст[-20:], поручение=поручение[-20:]):
                with сам.assertRaises(ValueError):
                    восстановление.предложить(текст, поручение)

    def test_удаление_второй_метки_не_подменяет_первое(сам):
        второе = МЕТКА.replace('sha256:' + 'a' * 64, 'sha256:' + 'b' * 64).encode()
        поручение = ПОРУЧЕНИЕ + второе + b'\n'
        with сам.assertRaisesRegex(ValueError, 'известному удалению'):
            восстановление.предложить(документ(ПОРУЧЕНИЕ + b'\n'), поручение)

    def test_длинная_ограда_и_вложенный_заголовок_сохраняются(сам):
        поручение = ПОРУЧЕНИЕ + '```text\n## Текст запроса\n```\n'.encode()
        повреждённое = документ(поручение.replace(МЕТКА.encode(), b'', 1))
        результат, _ = восстановление.предложить(повреждённое, поручение)
        сам.assertEqual(результат, документ(поручение))

    def test_нет_известного_удаления_нет_предложения(сам):
        with сам.assertRaisesRegex(ValueError, 'известному удалению'):
            восстановление.предложить(документ('Другой текст\n'.encode()), 'Исходный текст\n'.encode())


if __name__ == '__main__':
    unittest.main()

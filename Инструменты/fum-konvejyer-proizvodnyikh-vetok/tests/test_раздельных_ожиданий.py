"""Раздельные первичные наблюдения не скрывают позднее возобновление."""
import copy
import json
import unittest

from фикстура_остановленного_поколения import остановленное_поколение
from фикстура_раздельных_ожиданий import разделить, сохранить, событие
import завершение_сохранённых_писателей as завершение
import терминал_запуска


class ПроверкаРаздельныхОжиданий(unittest.TestCase):
    def test_два_подлинных_ответа_сохраняются_раздельно_и_повтор_идемпотентен(self):
        with остановленное_поколение() as (_, объект, запуск, план, вход, события, _):
            разделить(вход, события)
            до = объект.хранилище.прочитать()
            результат = завершение.предпросмотр(объект, вход)
            self.assertEqual('fum.завершённый-неудачный-запуск.3', результат['схема'])
            self.assertEqual(вход['ожидания'], {к: в['id'] for к, в in результат['ожидания'].items()})
            self.assertEqual(2, len({в['источник']['sha256'] for в in результат['ожидания'].values()}))
            self.assertEqual(до, объект.хранилище.прочитать())
            self.assertEqual(результат, завершение.завершить(объект, вход, результат['sha256']))
            после = объект.хранилище.путь.read_bytes()
            self.assertEqual(результат, завершение.завершить(объект, вход, результат['sha256']))
            self.assertEqual(после, объект.хранилище.путь.read_bytes())
            состояние = объект.хранилище.прочитать()
            self.assertEqual(результат, терминал_запуска.прочитать(состояние, план['запуск']))
            del состояние['приёмы'][терминал_запуска.ключ(план['запуск'])]
            self.assertEqual(до, состояние)
            with self.assertRaises(ValueError): объект.допустить(запуск, 'события')

    def test_старый_вход_не_принимает_неполный_общий_ответ(self):
        with остановленное_поколение() as (_, объект, _, _, вход, события, _):
            ответ = json.loads(события[-1]['payload']['item']['result']['content'][0]['text'])
            ответ['polls'].pop()
            события[-1]['payload']['item']['result']['content'][0]['text'] = json.dumps(ответ)
            сохранить(вход, события)
            with self.assertRaisesRegex(ValueError, 'наблюдения ребёнка'):
                завершение.предпросмотр(объект, вход)

    def test_старый_вход_по_прежнему_требует_idle(self):
        with остановленное_поколение() as (_, объект, _, _, вход, события, _):
            запись = события[-1]['payload']['item']['result']['content'][0]
            ответ = json.loads(запись['text']); ответ['polls'][0]['thread']['status'] = {'type': 'notLoaded'}
            запись['text'] = json.dumps(ответ); сохранить(вход, события)
            with self.assertRaisesRegex(ValueError, 'конечный ход'):
                завершение.предпросмотр(объект, вход)

    def test_перекрывающиеся_ожидания_и_подменённые_номера_отклоняются(self):
        with остановленное_поколение() as (_, объект, _, _, вход, события, _):
            исходные = разделить(вход, события)
            новые = copy.deepcopy(исходные); новые[-1]['payload']['started_at_ms'] = 9
            сохранить(вход, новые)
            with self.assertRaisesRegex(ValueError, 'последовательными'):
                завершение.предпросмотр(объект, вход)
            сохранить(вход, исходные)
            дети = list(вход['ожидания']); номера = list(вход['ожидания'].values())
            вход['ожидания'] = dict(zip(дети, reversed(номера)))
            with self.assertRaisesRegex(ValueError, 'адресованное'):
                завершение.предпросмотр(объект, вход)

    def test_возобновление_между_после_или_с_перекрытием_закрывает_переход(self):
        with остановленное_поколение() as (_, объект, _, _, вход, события, _):
            исходные = разделить(вход, события); задача = next(iter(вход['ожидания']))
            до = объект.хранилище.путь.read_bytes()
            for позиция, начало, конец in [(4, 10, 10), (5, 13, 14), (3, 8, 9), (3, 8, 10)]:
                with self.subTest(позиция=позиция, начало=начало, конец=конец):
                    новые = copy.deepcopy(исходные)
                    новые.insert(позиция, событие('send_message_to_thread', 'позднее',
                        {'threadId': задача, 'prompt': 'Продолжай'}, начало, конец))
                    сохранить(вход, новые)
                    with self.assertRaises(ValueError): завершение.предпросмотр(объект, вход)
                    self.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_позднее_неполное_ожидание_не_разрешает_старое_успешное(self):
        with остановленное_поколение() as (_, объект, _, _, вход, события, _):
            новые = разделить(вход, события); задача = next(iter(вход['ожидания']))
            новые.append(событие('wait_threads', 'позднее-неполное', {'targets': [{'threadId': задача}]}, 13, 14))
            сохранить(вход, новые)
            with self.assertRaises(ValueError): завершение.предпросмотр(объект, вход)

    def test_выгруженность_не_заменяет_правильный_конечный_ход(self):
        with остановленное_поколение() as (_, объект, _, _, вход, события, _):
            исходные = разделить(вход, события)
            for поле, значение in [('id', '00000000-0000-4000-8000-000000000999'), ('status', 'inProgress'), ('error', {'message': 'ошибка'})]:
                with self.subTest(поле=поле):
                    новые = copy.deepcopy(исходные); запись = новые[-2]['payload']['item']['result']['content'][0]
                    ответ = json.loads(запись['text']); ответ['polls'][0]['latestTurn'][поле] = значение
                    запись['text'] = json.dumps(ответ); сохранить(вход, новые)
                    with self.assertRaises(ValueError): завершение.предпросмотр(объект, вход)
            новые = copy.deepcopy(исходные); запись = новые[-2]['payload']['item']['result']['content'][0]
            ответ = json.loads(запись['text']); ответ['polls'][0]['thread']['status'] = {'type': 'running'}
            запись['text'] = json.dumps(ответ); сохранить(вход, новые)
            with self.assertRaisesRegex(ValueError, 'конечный ход'):
                завершение.предпросмотр(объект, вход)


if __name__ == '__main__':
    unittest.main()

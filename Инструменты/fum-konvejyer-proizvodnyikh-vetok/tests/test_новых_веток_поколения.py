"""Новое поколение не отбирает старые refs и не меняет логический состав."""
import copy
import unittest

from фикстура_новых_веток import новое_поколение, закрепить, хранение
from test_запуска_слоёв import ребёнок
from test_дочернего_назначения import прочитать as прочитать_ребёнком
from паспорт_конвейера import сформировать_ref_ветки
from план_запуска_слоёв import проверить_план


class ПроверкаНовыхВетокПоколения(unittest.TestCase):
    def test_новые_refs_и_полное_назначение_сохраняют_прежних_писателей(сам):
        with новое_поколение() as (корень, объект, старый, вход, описание, _, дети):
            до = объект.хранилище.прочитать()
            снимки = {с: (хранение.гит(д, 'symbolic-ref', 'HEAD'), хранение.гит(д, 'rev-parse', 'HEAD'),
                         хранение.гит(д, 'ls-files', '--stage', '-z'), (д / ('Память/' + с + '/поток.jsonl')).read_bytes())
                      for с, (д, _, _) in дети.items()}
            план = объект.предпросмотр(вход)
            сам.assertEqual(план, объект.подготовить(вход, план['sha256']))
            после = объект.хранилище.прочитать()
            сам.assertEqual(до['попытки'], после['попытки'])
            сам.assertEqual(до['приёмы'][старый['запуск']], после['приёмы'][старый['запуск']])
            for номер, слой in enumerate(описание['слои'], 101):
                имя = слой['слой']; допуск = объект.допустить(вход, имя)
                сам.assertTrue(допуск['разрешён_вызов'])
                сам.assertFalse(объект.допустить(вход, имя)['разрешён_вызов'])
                дерево, задача, источник = ребёнок(корень, вход, слой, допуск, номер, экранировать=True)
                наблюдение = объект.наблюдать(план['запуск'], имя, дерево, задача, источник)
                сам.assertEqual(наблюдение['схема'], 'fum.начальная-база-задачи.2')
                область = объект.область(план['запуск'], имя, вход['назначение'], источник)
                сам.assertEqual(область['база'], вход['постановка']['коммит'])
                собственное = прочитать_ребёнком({имя: (дерево, задача, источник)}, имя)
                сам.assertEqual(собственное['каталоги'], область['каталоги'])
                сам.assertEqual(собственное['писатель']['ref'], слой['ветка'])
            for с, (д, _, _) in дети.items():
                сам.assertEqual(снимки[с], (хранение.гит(д, 'symbolic-ref', 'HEAD'), хранение.гит(д, 'rev-parse', 'HEAD'),
                    хранение.гит(д, 'ls-files', '--stage', '-z'), (д / ('Память/' + с + '/поток.jsonl')).read_bytes()))

    def test_версии_ссылка_и_имя_ветки_не_подменяются(сам):
        with новое_поколение() as (_, объект, _, вход, план, _, _):
            сам.assertEqual(проверить_план(план), план)
            for изменить in (lambda п: п.update(схема='fum.запуск-двух-слоёв.3'),
                             lambda п: п['предыдущий'].update(терминал_sha256='f' * 64)):
                иной = copy.deepcopy(вход); изменить(иной)
                with сам.assertRaises(ValueError): объект.предпросмотр(иной)
            for изменить in (lambda п: п.update(схема='fum.план-запуска-двух-слоёв.1'),
                             lambda п: п['слои'][0].update(ветка=сформировать_ref_ветки(п['слои'][0]['каталог'], 'codex'))):
                иной = copy.deepcopy(план); изменить(иной)
                with сам.assertRaises(ValueError): проверить_план(иной)

    def test_состав_графа_и_история_предка_не_подменяются(сам):
        with новое_поколение() as (корень, объект, старый, вход, план, _, _):
            for поля in ({'роль': 'Другая роль'}, {'зависит_от': []}, {'каталог': 'Память/иная/'}):
                иной = copy.deepcopy(план); иной['слои'][1].update(поля)
                иной['слои'][1]['ветка'] = сформировать_ref_ветки(иной['слои'][1]['каталог'], 'codex') + '--g-' + иной['предыдущий']['терминал_sha256']
                закрепить(корень, вход, иной)
                до = объект.хранилище.путь.read_bytes()
                with сам.subTest(поля=поля), сам.assertRaisesRegex(ValueError, 'состав'):
                    объект.предпросмотр(вход)
                сам.assertEqual(до, объект.хранилище.путь.read_bytes())
            закрепить(корень, вход, план)
            with объект.хранилище.изменить() as состояние:
                состояние['попытки'][старый['попытки']['события']]['ответ']['подмена'] = True
            with сам.assertRaisesRegex(ValueError, 'история предшественника'):
                объект.предпросмотр(вход)

    def test_занятый_новый_ref_и_второй_C_не_создают_попытку(сам):
        with новое_поколение() as (корень, объект, _, вход, описание, _, _):
            план = объект.предпросмотр(вход); объект.подготовить(вход, план['sha256'])
            хранение.гит(корень, 'branch', описание['слои'][0]['ветка'].removeprefix('refs/heads/'))
            до = объект.хранилище.путь.read_bytes()
            with сам.assertRaisesRegex(ValueError, 'занята|конфликт'):
                объект.допустить(вход, 'события')
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())
            хранение.гит(корень, 'commit', '--allow-empty', '-qm', 'Сдвиг того же преемника')
            вход['постановка']['коммит'] = хранение.гит(корень, 'rev-parse', 'HEAD').strip()
            with сам.assertRaisesRegex(ValueError, 'неизменяемый'):
                объект.предпросмотр(вход)
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_чужой_запуск_с_другими_refs_сохраняет_каталоги(сам):
        with новое_поколение() as (_, объект, старый, вход, _, _, _):
            with объект.хранилище.изменить() as состояние:
                # Синтетическая чужая запись проверяет только фильтр резервирования.
                чужой = copy.deepcopy(состояние['приёмы'][старый['запуск']])
                for слой in чужой['план']['описание']['слои']:
                    слой['ветка'] += '--другой-писатель'
                состояние['приёмы']['f' * 64] = чужой
            до = объект.хранилище.путь.read_bytes()
            with сам.assertRaisesRegex(ValueError, 'Каталог.*другим запуском'):
                объект.предпросмотр(вход)
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())


if __name__ == '__main__':
    unittest.main()

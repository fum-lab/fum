    def test_сохранение_индекса_байтов_терминал_и_исторический_повтор(сам):
        with смешанное_создание() as (_, объект, пакет, план, вход, _, дети):
            модуль = сам.модуль()
            до = copy.deepcopy(объект.хранилище.прочитать())
            H, _, источник_H = дети['события']
            S, _, источник_S = дети['сообщения']
            индекс = хранение.гит(H, 'show', ':Память/события/поток.jsonl', сырые=True)
            рабочие = (H / 'Память/события/поток.jsonl').read_bytes()
            итог = модуль.предпросмотр(объект, вход)
            сам.assertEqual('остановлен-с-сохранением', итог['слои']['события']['вид'])
            сам.assertEqual('остановлен-до-записи', итог['слои']['сообщения']['вид'])
            сам.assertFalse(итог['отсутствие_незаписанного_вызова_доказано'])
            сам.assertEqual(итог, модуль.завершить(объект, вход, итог['sha256']))
            после = объект.хранилище.прочитать()
            ключ = терминал_запуска.ключ(план['запуск'])
            сам.assertEqual(итог, после['приёмы'].pop(ключ))
            сам.assertEqual(до, после)
            сам.assertEqual(индекс, хранение.гит(H, 'show', ':Память/события/поток.jsonl', сырые=True))
            сам.assertEqual(рабочие, (H / 'Память/события/поток.jsonl').read_bytes())
            сам.assertEqual('HEAD', хранение.гит(S, 'rev-parse', '--symbolic-full-name', 'HEAD').strip())
            сохранено = объект.хранилище.путь.read_bytes()
            источник_H.unlink(); источник_S.unlink(); Path(вход['источник']['путь']).unlink()
            сам.assertEqual(итог, модуль.завершить(объект, вход, итог['sha256']))
            сам.assertEqual(сохранено, объект.хранилище.путь.read_bytes())
            for слой in вход['слои']:
                with сам.assertRaises(ValueError):
                    объект.допустить(пакет, слой)

    def test_проверенный_дочерний_коммит_сохраняется_без_интеграции(сам):
        with смешанное_создание(с_коммитом=True) as (_, объект, _, _, вход, _, дети):
            модуль = сам.модуль()
            H, _, _ = дети['события']
            голова = хранение.гит(H, 'rev-parse', 'HEAD').strip()
            квитанция = Path(вход['слои']['события']['квитанция']['путь'])
            байты = квитанция.read_bytes()
            итог = модуль.предпросмотр(объект, вход)
            сам.assertEqual('остановлен-с-коммитом', итог['слои']['события']['вид'])
            сам.assertEqual(голова, итог['слои']['события']['H'])

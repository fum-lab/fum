"""Раздельные процессы CLI из настоящего временного C, без подмены допусков."""
import contextlib
import importlib
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import time

from фикстура_дочернего_коммита import фикстура, коммит, НОМЕР
from test_запуска_слоёв import хранение


def скопировать_инструменты(корень):
    исходный = Path(__file__).resolve().parents[3]
    файлы = set(исходный.glob('Инструменты/*/scripts/**/*.py'))
    файлы.update(исходный / 'Инструменты/fum-struktura-papok-zaprosov/шаблоны' / имя
        for имя in ('запрос.md.шаблон', 'отчёт.md.шаблон'))
    for путь in sorted(файлы):
        цель = корень / путь.relative_to(исходный)
        цель.parent.mkdir(parents=True, exist_ok=True)
        цель.write_bytes(путь.read_bytes())


def выполнить():
    фазы = []
    def измерить(стадия, действие):
        начало = time.perf_counter_ns()
        исход = 'отказ'
        try:
            результат = действие()
            исход = 'успех' if not isinstance(результат, subprocess.CompletedProcess) or результат.returncode == 0 else 'отказ'
            return результат
        finally:
            фазы.append({'стадия': стадия, 'наносекунды': time.perf_counter_ns() - начало, 'исход': исход})

    with фикстура(подготовить_базу=скопировать_инструменты) as (корень, источник, параметры):
        вход = корень.parent / 'вход-холодного-CLI.json'
        вход.write_bytes(хранение.байты(параметры))
        # Как у штатного CLI, новый процесс сначала загружает только создатель.
        # Меняется лишь адрес приватного хранилища; проверки не подменяются.
        запуск = ('import sys; from pathlib import Path; sys.path.insert(0, sys.argv.pop(1)); '
            'import создание_коммита as команда; '
            'assert "дочерний_коммит" not in sys.modules; '
            'команда.готовность.КОРЕНЬ_СОСТОЯНИЯ=Path(sys.argv.pop(1)); '
            'raise SystemExit(команда.главная())')
        def вызвать(стадия, *аргументы):
            return измерить(стадия, lambda: subprocess.run(
                [sys.executable, '-B', '-c', запуск,
                 str(корень / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts'),
                 str(корень.parent / 'готовность'), *аргументы], cwd=корень,
                env={**os.environ, 'CODEX_THREAD_ID': параметры['исполнитель']},
                capture_output=True, text=True, timeout=120))
        def отказ(результат):
            return {'код': результат.returncode, 'ошибка': результат.stderr.strip(),
                    'фазы': фазы, 'повтор_совпал': False, 'профиль_создания': []}

        результат = вызвать('подготовить в новом процессе', 'подготовить', '--вход', str(вход))
        if результат.returncode:
            return отказ(результат)
        свежесть = importlib.import_module('свежесть_слоя')
        def подготовить_проверку():
            план = свежесть.подготовить(корень, параметры['исполнитель'], источник)
            свежесть.применить(корень, параметры['исполнитель'], источник, план)
            хранение.гит(корень, 'add', '.')
            with contextlib.redirect_stdout(io.StringIO()):
                код = коммит.отчёты.выполнить_запуск(корень, параметры['запрос'],
                    'Проверить открытые байты холодного CLI', 'дочерний писатель', НОМЕР,
                    15, [sys.executable, '-c', "from pathlib import Path; assert Path('Память/события/данные.txt').read_text() == 'проверено\\n'"],
                    класс_проверки='адресная', приёмочные_раунды=True)
                if код:
                    raise AssertionError('Не прошла настоящая адресная проверка')
                коммит.отчёты.выполнить_предпросмотр(корень, параметры['запрос'])
            хранение.гит(корень, 'add', '.')
        измерить('свежесть, адресная проверка и индекс', подготовить_проверку)
        общие = ('--подготовка', параметры['подготовка'], '--проверка', НОМЕР)
        результат = вызвать('готово в новом процессе', 'готово', *общие, '--предел-секунд', '600')
        if результат.returncode:
            return отказ(результат)
        результат = вызвать('создать в новом процессе', 'создать', *общие)
        if результат.returncode:
            if хранение.гит(корень, 'rev-parse', 'HEAD').strip() != параметры['исходный_коммит']:
                raise AssertionError('Отказ неожиданно сдвинул HEAD')
            return отказ(результат)
        первый = json.loads(результат.stdout)
        повтор = вызвать('восстановить в новом процессе', 'создать', *общие)
        if повтор.returncode:
            return отказ(повтор)
        if (первый != json.loads(повтор.stdout)
                or первый['родители'] != [параметры['исходный_коммит']]
                or первый['коммит'] != хранение.гит(корень, 'rev-parse', 'HEAD').strip()
                or хранение.гит(корень, 'status', '--porcelain')
                or (корень / 'Журнал/README.md').exists() or (корень / 'Индексы').exists()):
            raise AssertionError('Повтор изменил коммит, родителей или собственную область')
        квитанция = json.loads(Path(параметры['квитанция']).read_bytes())
        return {'код': 0, 'ошибка': None, 'фазы': фазы, 'повтор_совпал': True,
                'профиль_создания': квитанция['профиль']}

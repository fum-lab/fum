from unittest import mock

from фикстура_смешанного_создания import смешанное_создание
from фикстура_дочернего_коммита import подготовить_передачу, коммит, НОМЕР
from фикстура_штатных_событий import служебный_контекст, копия_транспорта, изменение_файлов
from фикстура_двух_до_записи import обновить_источники
from test_завершения_запуска import граница
from test_запуска_слоёв import строка, хранение, ЗАДАЧА
from test_дочернего_коммита import ПроверкаДочернегоКоммита
import постановка_задачи as постановка
import приватный_вход_передачи as передача


def свидетельство(путь):
    путь = Path(путь)
    return {'путь': str(путь), 'sha256': коммит.хэш(путь.read_bytes())}


@contextmanager
def сохранение_поставки():
    with смешанное_создание() as (корень, объект, пакет, план, вход, события, дети):
        S, задача_S, источник_S = дети['сообщения']
        строки_S = [хранение.разобрать(с) for с in источник_S.read_bytes().splitlines()]
        конец_S = строки_S.pop()
        строки_S.insert(1, служебный_контекст())
        строки_S.append(копия_транспорта(строки_S[-1]))
        строки_S.append(изменение_файлов())
        источник_S.write_bytes(b''.join(строка(с) for с in строки_S))
        назначение = хранение.разобрать(хранение.гит(
            корень, 'show', пакет['постановка']['коммит'] + ':' + пакет['назначение'], сырые=True))
        слой_S = next(с for с in план['описание']['слои'] if с['слой'] == 'сообщения')
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=задача_S), \
                mock.patch.object(коммит.готовность, 'КОРЕНЬ_СОСТОЯНИЯ', корень.parent / 'готовность-S'):
            хранение.гит(S, 'switch', '-c', слой_S['ветка'].removeprefix('refs/heads/'))
            постановка.подтвердить_начало(S, задача_S, пакет['постановка']['коммит'], источник_S, с_поручением=True)
            поля = подготовить_передачу(S, задача_S, источник_S, пакет, назначение)
            каталог = корень.parent / 'передача-S'
            параметры = передача.создать_вход(S, источник_S, каталог,
                {к: поля[к] for к in передача.ПОЛЯ})
            файл = ПроверкаДочернегоКоммита().подготовить_готовность(S, источник_S, параметры)
            коммит.создать(файл, [НОМЕР])
        объект.наблюдать(план['запуск'], 'сообщения', S, задача_S, источник_S)
        строки_S.extend([изменение_файлов(), конец_S])
        источник_S.write_bytes(b''.join(строка(с) for с in строки_S))
        H, _, источник_H = дети['события']
        строки_H = [хранение.разобрать(с) for с in источник_H.read_bytes().splitlines()]
        строки_H.insert(-1, изменение_файлов())
        источник_H.write_bytes(b''.join(строка(с) for с in строки_H))
        удалённый = корень.parent / 'origin.git'
        хранение.гит(корень, 'init', '--bare', str(удалённый))
        хранение.гит(S, 'remote', 'add', 'origin', str(удалённый))
        oid = хранение.гит(S, 'rev-parse', 'HEAD').strip()
        хранение.гит(S, 'push', 'origin', oid + ':' + слой_S['ветка'])
        вход['схема'] = 'fum.завершение-неудачного-запуска.8'
        вход['слои']['сообщения'] = {**вход['слои']['сообщения'],
            'вид': 'остановлен-с-коммитом', 'источник': граница(источник_S),
            'подготовка': свидетельство(параметры['подготовка']),
            'квитанция': свидетельство(параметры['квитанция']),
            'пакет_передачи': свидетельство(каталог / 'пакет.json'),
            'публикация': {'коммит': oid, 'ref': слой_S['ветка'], 'адрес_sha256': хранение.хэш(str(удалённый))}}
        вход['слои']['события']['источник'] = граница(источник_H)
        обновить_источники(вход, события)
        yield корень, объект, пакет, план, вход, события, дети

"""Завершение поколения сохраняет оба грязных дерева и все прежние записи."""
import copy
import importlib
from pathlib import Path
import unittest
from unittest import mock

from фикстура_остановленного_поколения import остановленное_поколение, хранение, граница, строка, ЗАДАЧА
import терминал_запуска


class ПроверкаЗавершенияСохранённыхПисателей(unittest.TestCase):
    def модуль(сам):
        return importlib.import_module('завершение_сохранённых_писателей')

    def test_единственный_терминал_без_перезаписи_истории_и_детей(сам):
        with остановленное_поколение() as (_, объект, запуск, план, вход, _, дети):
            модуль = сам.модуль(); до = объект.хранилище.прочитать()
            результат = модуль.предпросмотр(объект, вход)
            сам.assertEqual(до, объект.хранилище.прочитать())
            сам.assertEqual(результат, модуль.завершить(объект, вход, результат['sha256']))
            после = объект.хранилище.прочитать(); ключ = терминал_запуска.ключ(план['запуск'])
            проверка = copy.deepcopy(после); del проверка['приёмы'][ключ]
            сам.assertEqual(проверка, до)
            байты = объект.хранилище.путь.read_bytes()
            сам.assertEqual(результат, модуль.завершить(объект, вход, результат['sha256']))
            сам.assertEqual(байты, объект.хранилище.путь.read_bytes())
            сам.assertEqual(результат['схема'], 'fum.завершённый-неудачный-запуск.2')
            with сам.assertRaises(ValueError):
                объект.допустить(запуск, 'события')
            with сам.assertRaises(ValueError):
                объект.наблюдать(план['запуск'], 'события', *дети['события'])
            with сам.assertRaises(ValueError):
                объект.сохранить(план['запуск'], 'события', вход['слои']['события']['попытка'], {'content': [], 'isError': False})

    def test_сдвиг_индекса_источника_или_ref_не_терминализируется(сам):
        for вид in ('индекс', 'источник', 'ref', 'квитанция'):
            with сам.subTest(вид=вид), остановленное_поколение() as (_, объект, _, _, вход, _, дети):
                модуль = сам.модуль(); результат = модуль.предпросмотр(объект, вход)
                дерево, _, источник = дети['события']
                if вид == 'индекс':
                    хранение.гит(дерево, 'add', '--', 'Память/события/поток.jsonl')
                elif вид == 'источник':
                    with источник.open('ab') as поток: поток.write(строка({'type': 'event_msg', 'payload': {'type': 'task_started'}}))
                elif вид == 'ref':
                    хранение.гит(дерево, 'switch', '-c', 'codex/чужая')
                else:
                    import постановка_задачи
                    постановка_задачи.путь_подтверждения(дерево).write_text('{}\n')
                до = объект.хранилище.путь.read_bytes()
                with сам.assertRaises(ValueError):
                    модуль.завершить(объект, вход, результат['sha256'])
                сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_чужой_пакет_и_неполная_аттестация_отклоняются(сам):
        with остановленное_поколение() as (_, объект, _, _, вход, _, _):
            модуль = сам.модуль()
            иной = copy.deepcopy(вход); иной['слои']['события']['пакет'] = иной['слои']['сообщения']['пакет']
            with сам.assertRaises(ValueError): модуль.предпросмотр(объект, иной)
            иной = copy.deepcopy(вход); иной['свидетельство_координатора']['ребёнок_не_возобновляется'] = False
            with сам.assertRaises(ValueError): модуль.предпросмотр(объект, иной)

    def test_неверный_конечный_ход_не_считается_остановкой(сам):
        with остановленное_поколение() as (_, объект, _, _, вход, _, дети):
            источник = дети['события'][2]
            данные = источник.read_bytes().splitlines(keepends=True)
            данные[-1] = строка({'type': 'event_msg', 'payload': {'type': 'task_complete', 'turn_id': ЗАДАЧА}})
            источник.write_bytes(b''.join(данные)); вход['слои']['события']['источник'] = граница(источник)
            with сам.assertRaises(ValueError): сам.модуль().предпросмотр(объект, вход)

    def test_сдвиг_после_первичной_проверки_до_записи_отклоняется(сам):
        with остановленное_поколение() as (_, объект, _, _, вход, _, дети):
            модуль = сам.модуль(); результат = модуль.предпросмотр(объект, вход)
            настоящая = модуль.сохранённый_писатель.проверить
            сдвинут = False
            def сдвиг(*аргументы):
                nonlocal сдвинут
                проверка = настоящая(*аргументы)
                if not сдвинут:
                    хранение.гит(дети['события'][0], 'add', '--', 'Память/события/поток.jsonl')
                    сдвинут = True
                return проверка
            до = объект.хранилище.путь.read_bytes()
            with mock.patch.object(модуль.сохранённый_писатель, 'проверить', side_effect=сдвиг):
                with сам.assertRaises(ValueError): модуль.завершить(объект, вход, результат['sha256'])
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())

    def test_старый_терминал_не_заменяется_новым(сам):
        with остановленное_поколение() as (_, объект, _, план, вход, _, _):
            модуль = сам.модуль(); старый = модуль.предпросмотр(объект, вход)
            старый['схема'] = терминал_запуска.СХЕМА
            del старый['sha256']; старый['sha256'] = хранение.хэш(старый)
            with объект.хранилище.изменить() as состояние:
                состояние['приёмы'][терминал_запуска.ключ(план['запуск'])] = старый
            до = объект.хранилище.путь.read_bytes()
            with сам.assertRaisesRegex(ValueError, 'терминал'):
                модуль.предпросмотр(объект, вход)
            сам.assertEqual(до, объект.хранилище.путь.read_bytes())


if __name__ == '__main__':
    unittest.main()

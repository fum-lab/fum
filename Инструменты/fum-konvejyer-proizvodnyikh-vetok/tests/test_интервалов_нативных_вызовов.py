"""Начало ожидания берётся из интервала runtime, а не из позиции ответа."""
import copy
import importlib
from pathlib import Path
import tempfile
import unittest

from test_завершения_запуска import граница, вызов, строка, ЗАДАЧА
import нативные_вызовы

РЕБЁНОК = '11111111-1111-4111-8111-111111111111'


def событие(инструмент, номер, аргументы, начало, конец):
    запись = вызов(инструмент, номер, аргументы, {'content': [], 'isError': False})
    запись['payload'].update(started_at_ms=начало, completed_at_ms=конец)
    return запись


def прочитать(события, интервалы=True):
    with tempfile.TemporaryDirectory() as временный:
        путь = Path(временный).resolve() / 'источник.jsonl'
        путь.write_bytes(b''.join(строка(з) for з in [
            {'type': 'session_meta', 'payload': {'id': ЗАДАЧА}}, *события]))
        параметры = {'интервалы': True} if интервалы else {}
        return нативные_вызовы.прочитать(граница(путь, корень=True), ЗАДАЧА, ожидания=[РЕБЁНОК], **параметры)


class ПроверкаИнтерваловВызовов(unittest.TestCase):
    def test_интервал_связан_с_сырой_записью_старый_вывод_не_меняется(сам):
        события = [событие('wait_threads', 'ожидание', {'targets': [{'threadId': РЕБЁНОК}]}, 20, 30)]
        новый = прочитать(события)
        сам.assertEqual(новый['схема'], 'fum.наблюдённые-вызовы-запуска.2')
        сам.assertEqual(новый['ожидания'][0]['интервал'], {'начало_мс': 20, 'конец_мс': 30})
        сам.assertEqual(новый['ожидания'][0]['инструмент'], 'wait_threads')
        старый = прочитать(события, интервалы=False)
        сам.assertEqual(старый['схема'], 'fum.наблюдённые-вызовы-запуска.1')
        сам.assertNotIn('интервал', старый['ожидания'][0])
        сам.assertEqual(старый['ожидания'][0]['источник'], новый['ожидания'][0]['источник'])

    def test_неизвестный_или_обратный_интервал_не_додумывается(сам):
        for начало, конец in [(None, 2), (True, 2), (-1, 2), (5, 4), (1, '2')]:
            with сам.subTest(начало=начало, конец=конец), сам.assertRaises(ValueError):
                прочитать([событие('wait_threads', 'ожидание', {'targets': [{'threadId': РЕБЁНОК}]}, начало, конец)])

    def test_последнее_ожидание_после_уточнения_без_перекрытия(сам):
        модуль = importlib.import_module('последнее_ожидание')
        события = [событие('send_message_to_thread', 'уточнение', {'threadId': РЕБЁНОК, 'prompt': 'Остановись'}, 10, 20),
                   событие('wait_threads', 'ожидание', {'targets': [{'threadId': РЕБЁНОК}]}, 21, 30)]
        результат = прочитать(события)
        сам.assertEqual(модуль.проверить(результат, 'ожидание', [РЕБЁНОК]), результат['ожидания'][0])
        for начало in (15, 20):
            пересечение = copy.deepcopy(события); пересечение[1]['payload']['started_at_ms'] = начало
            with сам.subTest(начало=начало), сам.assertRaisesRegex(ValueError, 'после|перекры'):
                модуль.проверить(прочитать(пересечение), 'ожидание', [РЕБЁНОК])
        поздний = события + [событие('send_message_to_thread', 'позднее', {'threadId': РЕБЁНОК, 'prompt': 'Продолжай'}, 40, 50)]
        with сам.assertRaises(ValueError):
            модуль.проверить(прочитать(поздний), 'ожидание', [РЕБЁНОК])
        перенос = copy.deepcopy(события); перенос[0]['payload']['item']['tool'] = 'handoff_thread'
        with сам.assertRaises(ValueError):
            модуль.проверить(прочитать(перенос), 'ожидание', [РЕБЁНОК])


if __name__ == '__main__':
    unittest.main()

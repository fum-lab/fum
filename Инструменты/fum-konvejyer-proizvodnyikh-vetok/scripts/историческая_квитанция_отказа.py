"""Чистая сверка неизвестного исторического эффекта; не допуск повторной доставки."""
import hashlib
from pathlib import Path, PurePosixPath
import stat

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import конверт_приёма as конверт
import эпизод_приёма as эпизод

хранение = эпизод.хранение


def проверить(сырые, основание, пакет, защищённые):
    хранение.требовать(type(сырые) is bytes, 'Нужны исходные байты квитанции')
    запись = хранение.разобрать(сырые)
    хранение.поля(запись, {'данные', 'sha256'})
    хранение.требовать(хранение.байты(запись) == сырые
        and хранение.хэш(запись['данные']) == запись['sha256'], 'Изменены канонические байты квитанции')
    блок = конверт.проверить(пакет, пакет['текст'])
    эпизод.проверить_основание(основание)
    источник = пакет['план']['источник']
    хранение.требовать(основание['поручение'] == блок
        and блок['план'] == пакет['план']['идентификатор']
        and блок['срез'] == основание['срез'] == источник['срез']
        and блок['источник_приёмки'] == источник['коммит']
        and блок['корневая_задача'] == источник['владелец']
        and основание['дерево'] == источник['дерево']
        and основание['журнал'] == блок['журнал'] and основание['проверка'] == блок['проверка'],
        'Намерение не совпало с поручением и планом')
    хранение.требовать(type(защищённые) is dict, 'Нужен снимок защищённых данных')
    for имя, значение in защищённые.items():
        хранение.требовать(type(имя) is str and имя and '\0' not in имя and '\\' not in имя
            and not PurePosixPath(имя).is_absolute() and имя != '.'
            and PurePosixPath(имя).as_posix() == имя and '..' not in PurePosixPath(имя).parts,
            'Неверный путь защищённых данных')
        хранение.поля(значение, {'режим', 'sha256'})
        хранение.требовать(type(значение['режим']) is int
            and (stat.S_ISREG(значение['режим']) or stat.S_ISLNK(значение['режим']))
            and хранение.шестнадцатеричный(значение['sha256']), 'Неверный снимок защищённых данных')
    ожидаемое = {'схема': 'fum.квитанция-обратной-доставки.2', 'план': блок['план'],
        'корень': блок['корень'], 'ref': блок['ref'], 'владелец': блок['исполнитель'],
        'источник': блок['срез'], 'до': блок['исходный_коммит'], 'стадия': 'эффект не подтверждён',
        'дерево': основание['дерево'], 'защищённые': защищённые, 'проверка': None,
        'коммит': None, 'публикация': None, 'получатель': 'unknown', 'основание': None, 'отчёт': None}
    хранение.требовать(хранение.байты(запись['данные']) == хранение.байты(ожидаемое),
        'Историческая квитанция другого получателя, эффекта или состояния')
    return {'схема': 'fum.прочитанная-историческая-квитанция-отказа.1',
        'исполнитель': блок['исполнитель'], 'план': блок['план'],
        'до': блок['исходный_коммит'], 'срез': блок['срез'], 'дерево': основание['дерево'],
        'источник_sha256': hashlib.sha256(сырые).hexdigest(), 'квитанция_sha256': запись['sha256'],
        'основание_sha256': основание['sha256'], 'конверт_sha256': пакет['sha256'],
        'исход_эффекта': 'unknown', 'повтор_эффекта_разрешён': False}

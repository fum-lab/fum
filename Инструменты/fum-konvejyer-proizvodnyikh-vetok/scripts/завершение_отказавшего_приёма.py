КОД[Path(__file__).resolve()] = КОД_ПРИ_ЗАГРУЗКЕ


def _основа(исполнитель, вход, состояние):
    запись = исполнитель._прочитать(состояние, вход['запуск']); план = запись['план']
    хранение.требовать(план['sha256'] == вход['план_sha256']
        and запись['смысл']['схема'] == 'fum.запуск-двух-слоёв.7'
        and set(запись['наблюдения']) == set(слои)
        and all(type(н) is dict for н in запись['наблюдения'].values()), 'Нужны два наблюдённых писателя .7')
    координатор = прежний.общие._координатор(исполнитель, вход, план, состояние)
    исполнитель._инструменты(координатор['HEAD'])
    for путь_кода, хэш_кода in КОД.items():
        хранение.безопасный_путь(путь_кода)
        хранение.требовать(hashlib.sha256(путь_кода.read_bytes()).hexdigest() == хэш_кода, 'Код терминала отказавшего приёма изменился')
    аттестация = {'задача': исполнитель.задача, 'единственный_координатор': True,
        'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}
    хранение.требовать(вход['свидетельство_координатора'] == аттестация, 'Нет аттестации остановки координатора')
    база = план['координатор']['HEAD']; смысл = запись['смысл']
    манифест = прежний.манифест_коммита(исполнитель.корень, база, смысл['постановка']['файлы'])
    хранение.требовать(смысл['план'] in манифест and смысл['назначение'] in манифест
        and хранение.разобрать(манифест[смысл['план']]) == план['описание'], 'Подменён манифест C')
    области = прежний.область_писателя.каталоги_назначения(исполнитель.корень, база, исполнитель.задача,
        смысл['план'], план['описание'], хранение.разобрать(манифест[смысл['назначение']]))
    попытки = {имя: состояние['попытки'].get(ключ) for имя, ключ in план['попытки'].items()}
    ветки = {с['слой']: с['ветка'] for с in план['описание']['слои']}
    дети = [вход['слои'][имя]['задача'] for имя in слои]
    корни = [вход['слои'][имя]['корень'] for имя in слои]
    хранение.требовать(len(set(дети)) == len(set(корни)) == 2, 'Повтор ребёнка или дерева')
    for имя in слои:
        п = попытки[имя]; ребёнок = вход['слои'][имя]
        хранение.требовать(type(п) is dict and п['аргументы'] == план['аргументы'][имя]
            and п['база'] == база and type(п['ответ']) is dict
            and ребёнок['попытка'] == п['попытка'], 'Изменена первоначальная попытка писателя')
        хранение.требовать(состояние['писатели'].get(ребёнок['корень'])
            in (None, {'задача': ребёнок['задача'], 'ref': ветки[имя]})
            and not any(к != ребёнок['корень'] and в['ref'].casefold() == ветки[имя].casefold()
                for к, в in состояние['писатели'].items()), 'Другой писатель присвоил область ребёнка')
    return запись, план, попытки, области, ветки, координатор, аттестация


def _корень(исполнитель, вход, попытки):
    дети = [вход['слои'][имя]['задача'] for имя in слои]
    аргументы = [попытки[имя]['аргументы'] for имя in слои]
    старый = вход['первоначальный_источник']; полный = вход['источник']
    хранение.требовать(старый['путь'] == полный['путь'] and старый['начало'] == полный['начало']
        and старый['начало_sha256'] == полный['начало_sha256'], 'Нужен прежний префикс того же ROOT-снимка')
    раньше = прежний.нативные_вызовы.прочитать_префикс(старый, исполнитель.задача,
        аргументы=аргументы, ожидания=дети, интервалы=True)
    хранение.требовать(раньше['возобновления'] == [], 'Первоначальный ROOT уже содержит обратный send')
    ожидания = первоначальные_ожидания_поставок.проверить(раньше, вход['первоначальные_ожидания'], дети)
    вызовы = раньше['вызовы']
    хранение.требовать(len(вызовы) == 2 and [в['аргументы'] for в in вызовы] == аргументы
        and вызовы[0]['источник']['конец'] <= вызовы[1]['источник']['начало']
        and вызовы[0]['интервал']['конец_мс'] < вызовы[1]['интервал']['начало_мс'],
        'Нужны единственные первоначальные создания H затем S')
    for имя, в in zip(слои, вызовы):
        ответ = попытки[имя]['ответ']
        хранение.требовать(прежний.извлечь_ответ(в['ответ']) == ответ
            and not ответ.get('противоречивые_идентификаторы')
            and ответ.get('threadId') in (None, вход['слои'][имя]['задача']), 'Чужой ответ первоначального создания')
    сейчас = прежний.нативные_вызовы.прочитать(полный, исполнитель.задача,
        аргументы=аргументы, ожидания=дети, интервалы=True)
    хранение.требовать(сейчас['вызовы'] == вызовы, 'Создания изменились после первоначальной остановки')
    новые = ожидания_обратного_приёма.проверить(сейчас, вход['ожидания_приёма'], вход['отправки'],
        последовательные_приёмы=False)
    по_детям = {в['аргументы']['threadId']: в for в in сейчас['возобновления']}
    первая, вторая = [по_детям[ребёнок] for ребёнок in дети]
    хранение.требовать(первая['источник']['конец'] <= вторая['источник']['начало']
        and первая['интервал']['конец_мс'] < вторая['интервал']['начало_мс'], 'Обратный send H должен предшествовать S')
    хранение.требовать(старый['граница'] <= первая['источник']['начало']
        and all(о['интервал']['конец_мс'] < первая['интервал']['начало_мс'] for о in ожидания.values()),
        'Первоначальная остановка перекрыла обратный приём')
    return сейчас, ожидания, новые, по_детям


def _приём(исполнитель, вход, имя, поставлено, сырые, идентичность,
        отправка, ожидание, прежнее_ожидание, кеш):
    р = вход['приёмы'][имя]; ребёнок = вход['слои'][имя]
    хранение.поля(р, {'вид', 'текст', 'цель', 'свидетельства', 'артефакт'})
    хранение.требовать(р['цель']['задача'] == ребёнок['задача'] and р['цель']['корень'] == ребёнок['корень'],
        'Локатор CLI относится к другому писателю')
    блок = файлы.конверт.разобрать_текст(р['текст'])
    хранение.требовать(блок['корневая_задача'] == исполнитель.задача and блок['слой'] == имя
        and блок['исполнитель'] == ребёнок['задача'] and блок['корень'] == ребёнок['корень']
        and блок['ref'] == поставлено['ref'] and блок['база'] == поставлено['C']
        and блок['назначение_sha256'] == поставлено['назначение_sha256']
        and блок['исходный_коммит'] == поставлено['S'], 'Приём другого первоначального коммита или назначения')
    байты_канала = None
    if р['вид'] == 'saved-wrapper': байты_канала = канал.прочитать(р['артефакт'], ребёнок['задача'])
    else: хранение.требовать(р['артефакт'] is None, 'Канал не относится к прямому отказу')
    связь = продолжение.проверить(сырые, ребёнок['источник'], исполнитель.задача, р['текст'],
        отправка, ожидание, р['цель'], вид=р['вид'], канал=байты_канала, артефакт=р['артефакт'])
    источник_пакета = str(файлы.конверт.адрес(р['текст'], получатель=True) / 'нативный/источник.jsonl')
    файловая = файлы.прочитать(р['свидетельства'], р['текст'], источник_пакета, сверки=кеш)
    пакет = прежний.поставка._свидетельство(р['свидетельства']['конверт'])
    с = пакет['свидетельство']
    хранение.поля(с, {'схема', 'координатор', 'остановка', 'ожидание', 'возобновление'})
    хранение.требовать(с['схема'] == 'fum.свидетельство-дочернего-приёма.1'
        and с['ожидание'] == вход['первоначальные_ожидания'][ребёнок['задача']]
        and с['возобновление'] == отправка['id']
        and {к: с['остановка'][к] for к in ('граница','sha256')}
            == {к: ребёнок['источник'][к] for к in ('граница','sha256')}, 'Конверт подменил прежнюю остановку или send')
    хэш_остановки = архивы.остановка(с['остановка'], сырые, сверки=кеш)
    нативный = кеш.прочитать(с['координатор'], исполнитель.задача,
        [вход['слои'][и]['задача'] for и in слои])
    хранение.требовать(отправка in нативный['возобновления'], 'Конверт не содержит своего первичного send')
    до_отправки = [о for о in нативный['ожидания']
        if ребёнок['задача'] in {ц['threadId'] for ц in о['аргументы']['targets']}
        and о['источник']['конец'] <= отправка['источник']['начало']]
    хранение.требовать(до_отправки and до_отправки[-1] == прежнее_ожидание,
        'Архив не подтверждает последнее первоначальное ожидание ребёнка')
    вход_проверен = замороженный.проверить(пакет, р['текст'], сырые, идентичность,
        ребёнок['источник']['путь'], прежнее_ожидание, отправка, связь, файловая, р['цель'], сверки=кеш)
    хранение.гит(исполнитель.корень, 'merge-base', '--is-ancestor', блок['источник_приёмки'], вход['координатор']['HEAD'])
    if байты_канала is not None:
        хранение.требовать(канал.прочитать(р['артефакт'], ребёнок['задача']) == байты_канала, 'Канал отказа сдвинулся')
        кеш.сохранить_сверку(lambda: хранение.требовать(
            канал.прочитать(р['артефакт'], ребёнок['задача']) == байты_канала, 'Канал отказа сдвинулся'))
    return {'поручение': блок, 'нативный': связь, 'файловый': файловая,
        'замороженный_вход': вход_проверен, 'архив_остановки_sha256': хэш_остановки,
        'повтор_эффекта_разрешён': False}


def _план(исполнитель, вход, состояние, *, профиль=None, сверки=None):
    начало = последняя = time.monotonic_ns()
    def метка(имя):
        nonlocal последняя
        теперь = time.monotonic_ns()
        if профиль is not None: профиль[имя] = теперь - последняя
        последняя = теперь
    хранение.поля(вход, {'схема', 'запуск', 'план_sha256', 'координатор', 'источник', 'первоначальный_источник',
        'первоначальные_ожидания', 'слои', 'отправки', 'ожидания_приёма', 'приёмы', 'свидетельство_координатора'})
    хранение.требовать(вход['схема'] == 'fum.завершение-неудачного-запуска.9', 'Неизвестный терминал обратного отказа')
    хранение.требовать(профиль is None or type(профиль) is dict, 'Нужен словарь профиля')
    история = прежний._история(исполнитель, состояние, вход['запуск'])
    готовый = терминал.прочитать(состояние, вход['запуск'])
    if готовый is not None:
        хранение.требовать(готовый['схема'] == терминал.СХЕМА_ОТКАЗАВШЕГО_ПРИЁМА
            and готовый['вход_sha256'] == хранение.хэш(вход) and готовый['история_sha256'] == история,
            'Повтор изменил вход или историю отказавшего приёма')
        return copy.deepcopy(готовый)
    хранение.поля(вход['слои'], set(слои)); хранение.поля(вход['приёмы'], set(слои))
    запись, план, попытки, области, ветки, координатор, аттестация = _основа(исполнитель, вход, состояние)
    метка('основание')
    кеш = архивы.АрхивыПриёма(вход['источник'])
    нативный, старые, новые, отправки = _корень(исполнитель, вход, попытки)
    метка('ROOT')
    поставки, отказы = {}, {}
    for имя in слои:
        ребёнок = вход['слои'][имя]
        аргументы_поставки = (исполнитель, ребёнок, запись, запись['наблюдения'][имя], попытки[имя],
            план['координатор']['HEAD'], области[имя], ветки[имя], старые[ребёнок['задача']])
        поставки[имя] = прежний.поставка.проверить_префикс(*аргументы_поставки, слой=имя)
        сырые, идентичность, _ = прежний.поток.прочитать_префикс(ребёнок['источник'], ребёнок['задача'], ребёнок['корень'],
            план['координатор']['HEAD'], попытки[имя]['аргументы']['model'],
            попытки[имя]['аргументы']['thinking'], старые[ребёнок['задача']])
        отказы[имя] = _приём(исполнитель, вход, имя, поставки[имя], сырые, идентичность,
            отправки[ребёнок['задача']], новые[ребёнок['задача']], старые[ребёнок['задача']], кеш)
        метка(имя)
    б = [отказы[и]['поручение'] for и in слои]
    хранение.требовать(all(б[0][к] == б[1][к] for к in ('план','срез','источник_приёмки')),
        'Два отказа относятся к разным интеграциям')
    хранение.требовать(прежний.общие._координатор(исполнитель, вход, план, состояние) == координатор
        and прежний._история(исполнитель, состояние, вход['запуск']) == история, 'Основания сдвинулись при чтении')
    if сверки is None: кеш.сверить()
    else: сверки.append(кеш)
    тело = {'схема': терминал.СХЕМА_ОТКАЗАВШЕГО_ПРИЁМА, 'запуск': вход['запуск'], 'план_sha256': план['sha256'],
        'вход_sha256': хранение.хэш(вход), 'история_sha256': история, 'координатор': координатор,
        'слои': поставки, 'приёмы': отказы, 'источник': нативный['источник'],
        'свидетельство_координатора': аттестация, 'отсутствие_незаписанного_вызова_доказано': False,
        'повтор_неизвестных_эффектов_разрешён': False}
    итог = {**тело, 'sha256': хранение.хэш(тело)}
    метка('заключительная_сверка')
    if профиль is not None: профиль['всего'] = time.monotonic_ns() - начало
    return итог


def предпросмотр(исполнитель, вход, *, профиль=None):
    return _план(исполнитель, вход, исполнитель.хранилище.прочитать(), профиль=профиль)


def завершить(исполнитель, вход, ожидаемый_хэш):
    with исполнитель.хранилище.изменить() as состояние:
        итог = _план(исполнитель, вход, состояние)
        хранение.требовать(итог['sha256'] == ожидаемый_хэш, 'Изменён просмотренный терминал отказов')
        ключ = терминал.ключ(вход['запуск'])
        if ключ not in состояние['приёмы']:
            сверки = []
            хранение.требовать(_план(исполнитель, вход, состояние, сверки=сверки) == итог, 'Свидетельства сдвинулись перед терминалом')
            исполнитель.хранилище.проверить_владельца_под_замком(состояние,
                ожидаемый_коммит=вход['координатор']['HEAD'], ожидаемая_ветка=вход['координатор']['ref'])
            for снимок in сверки: снимок.сверить()
            состояние['приёмы'][ключ] = итог
        return copy.deepcopy(итог)

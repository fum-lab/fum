"""Проверка собственной пары J; импорт проверяется как целое дерево S."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import коммит_приёма
import свежесть_слоя


def проверить(параметры, сообщение, валидатор):
    коммит_приёма.проверить(параметры, окончательно=True)
    корень = Path(параметры['корень']); запрос = корень / параметры['запрос']; отчёт = запрос.with_name('отчёт.md')
    текст = запрос.read_text(encoding='utf-8'); ошибки = []
    ошибки.extend(валидатор.validate_request_filename_title(запрос))
    if not текст.startswith(валидатор.expected_request_heading(запрос) + '\n'):
        ошибки.append('Неверный заголовок запроса приёма')
    навигация = валидатор.section_body(текст, 'Навигация по запросам')
    ожидаемая = '- Предыдущий запрос: отложен до передачи координатору\n- Следующий запрос: отложен до передачи координатору'
    if навигация is None or навигация.strip() != ожидаемая:
        ошибки.append('Неверная отложенная навигация приёма')
    ошибки.extend(валидатор.validate_journal(корень, запрос, контрольная_точка=True))
    ошибки.extend(валидатор.validate_used_tools_section(текст, запрос))
    ошибки.extend(валидатор.validate_codex_commit_context_requirements(запрос, параметры['задача'], сообщение))
    ошибки.extend(валидатор.validate_codex_thread_id_section(текст, запрос, expected_codex_thread_id=параметры['задача']))
    ошибки.extend(валидатор.validate_commit_message_codex_thread_id(текст, запрос, сообщение))
    затронутые, отказ = валидатор.affected_files_from_request(текст, запрос, корень)
    ошибки.extend(отказ)
    if not {запрос, отчёт} <= set(затронутые):
        ошибки.append('В охвате не названа пара приёма')
    свои = {запрос, отчёт}
    ошибки.extend(валидатор.validate_markdown_links(свои, корень))
    ошибки.extend(валидатор.validate_meta_request_coverage(свои, корень))
    ошибки.extend(валидатор.validate_provenance_section_position(свои, корень))
    ошибки.extend(валидатор.validate_mermaid_markdown_list_labels(свои, корень))
    время = свежесть_слоя.свежесть.format_msk(свежесть_слоя.свежесть.parse_now())
    for путь in свои:
        ошибки.extend(валидатор.проверить_незаполненный_маркер_шаблона(путь.read_text(), путь, корень))
        _, нарушения, _ = свежесть_слоя.свежесть.process_markdown_file(путь, корень,
            set(параметры['разрешённые_цели']), время, True, False)
        ошибки.extend(нарушения)
    # Создатель после связности ещё проверяет адрес, индекс, v4 и готовность,
    # затем повторяет полный допуск перед эффектом. Второй полный читатель
    # внутри этой read-only проверки не создаёт дополнительной границы эффекта.
    return ошибки

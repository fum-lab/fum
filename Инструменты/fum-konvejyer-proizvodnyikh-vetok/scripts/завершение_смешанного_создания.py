КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
_снимок_корня = общие._снимок_корня


def _история(исполнитель, состояние, запуск):
    запись = исполнитель._прочитать(состояние, запуск)
    попытки = {имя: состояние['попытки'].get(ключ) for имя, ключ in запись['план']['попытки'].items()}
    return хранение.хэш({'запись': запись, 'попытки': попытки})


def _ветки(исполнитель, вход, план, состояние):
    координатор = завершение_сохранённых_писателей._координатор(исполнитель, вход, план, состояние)
    H, S = вход['слои']['события'], вход['слои']['сообщения']
    слои = {с['слой']: с for с in план['описание']['слои']}
    писатели = состояние['писатели']
    ветка_H, ветка_S = слои['события']['ветка'], слои['сообщения']['ветка']
    хранение.требовать(писатели.get(H['корень']) in (None, {'задача': H['задача'], 'ref': ветка_H})
        and not any(корень != H['корень'] and п['ref'].casefold() == ветка_H.casefold()
                    for корень, п in писатели.items()), 'Другое дерево или UUID присвоило назначенного писателя H')
    ветки = {в.casefold() for в in хранение.гит(исполнитель.корень,
        'for-each-ref', '--format=%(refname)', 'refs/heads/').splitlines()}
    хранение.требовать(ветка_S.casefold() not in ветки and S['корень'] not in писатели
        and not any(п['ref'].casefold() == ветка_S.casefold() for п in писатели.values()),
        'S уже имеет ветку или зарегистрированного писателя')
    return координатор


def _план(исполнитель, вход, состояние):
    хранение.поля(вход, {'схема', 'запуск', 'план_sha256', 'координатор', 'источник', 'ожидания',
        'слои', 'возобновления', 'свидетельство_координатора'})
    хранение.требовать(вход['схема'] == 'fum.завершение-неудачного-запуска.7', 'Неизвестный смешанный переход создания')
    запись = исполнитель._прочитать(состояние, вход['запуск']); план = запись['план']
    хранение.требовать(план['sha256'] == вход['план_sha256']
        and запись['смысл']['схема'] == 'fum.запуск-двух-слоёв.7'
        and set(запись['наблюдения']) == {'события', 'сообщения'}
        and type(запись['наблюдения']['события']) is dict and запись['наблюдения']['сообщения'] is None,
        'Нужен наблюдённый писатель H и неназначенный созданный S')
    история = _история(исполнитель, состояние, вход['запуск'])
    прежний = терминал_запуска.прочитать(состояние, вход['запуск'])
    if прежний is not None:
        хранение.требовать(прежний['схема'] == терминал_запуска.СХЕМА_СМЕШАННОГО_СОЗДАНИЯ
            and прежний['вход_sha256'] == хранение.хэш(вход) and прежний['история_sha256'] == история,
            'Повтор изменил смешанный терминал или историю')
        return copy.deepcopy(прежний), []
    хранение.требовать(вход['возобновления'] == {}, 'Смешанное создание пока не допускает возобновлений')
    хранение.поля(вход['слои'], {'события', 'сообщения'})
    S = вход['слои']['сообщения']
    хранение.поля(S, {'вид', 'попытка', 'задача', 'корень', 'источник'})
    хранение.требовать(S['вид'] == 'остановлен-до-записи', 'S должен остановиться до первой записи')
    попытки = {имя: состояние['попытки'].get(ключ) for имя, ключ in план['попытки'].items()}
    база = план['координатор']['HEAD']
    for имя, попытка in попытки.items():
        хранение.требовать(type(попытка) is dict and попытка['аргументы'] == план['аргументы'][имя]
            and попытка['база'] == база and type(попытка['ответ']) is dict
            and вход['слои'][имя]['попытка'] == попытка['попытка'], 'Нужны два настоящих сохранённых создания')
    дети = [вход['слои'][имя]['задача'] for имя in ('события', 'сообщения')]
    корни = [вход['слои'][имя]['корень'] for имя in ('события', 'сообщения')]
    хранение.требовать(len(set(дети)) == len(set(корни)) == 2, 'Повтор UUID или дерева ребёнка')
    координатор = _ветки(исполнитель, вход, план, состояние)
    исполнитель._инструменты(координатор['HEAD'])
    for путь, хэш in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == хэш, 'Код смешанного закрытия изменился')
    аттестация = {'задача': исполнитель.задача, 'единственный_координатор': True,
        'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}
    хранение.требовать(вход['свидетельство_координатора'] == аттестация, 'Нет кооперативной аттестации остановки')
    смысл = запись['смысл']; файлы = манифест_коммита(исполнитель.корень, база, смысл['постановка']['файлы'])
    хранение.требовать(смысл['план'] in файлы and смысл['назначение'] in файлы
        and хранение.разобрать(файлы[смысл['план']]) == план['описание'], 'Подменён манифест C')
    области = область_писателя.каталоги_назначения(исполнитель.корень, база, исполнитель.задача,
        смысл['план'], план['описание'], хранение.разобрать(файлы[смысл['назначение']]))
    нативный = нативные_вызовы.прочитать(вход['источник'], исполнитель.задача,
        аргументы=[попытки[имя]['аргументы'] for имя in ('события', 'сообщения')], ожидания=дети, интервалы=True)
    ожидания = раздельные_ожидания.проверить(нативный, вход['ожидания'], дети)
    вызовы = нативный['вызовы']
    хранение.требовать(len(вызовы) == 2
        and [в['аргументы'] for в in вызовы] == [попытки[имя]['аргументы'] for имя in ('события', 'сообщения')]
        and вызовы[0]['источник']['конец'] <= вызовы[1]['источник']['начало']
        and вызовы[0]['интервал']['конец_мс'] < вызовы[1]['интервал']['начало_мс'],
        'Нужны последовательные единственные создания H затем S')
    for имя, вызов in zip(('события', 'сообщения'), вызовы):
        ответ = попытки[имя]['ответ']
        хранение.требовать(извлечь_ответ(вызов['ответ']) == ответ
            and not ответ.get('противоречивые_идентификаторы')
            and ответ.get('threadId') in (None, вход['слои'][имя]['задача']), 'Ответ создания расходится с ребёнком')
    H = вход['слои']['события']
    ветка_H = next(с['ветка'] for с in план['описание']['слои'] if с['слой'] == 'события')
    if H.get('вид') == 'остановлен-с-коммитом':
        функция_H = закоммиченный_писатель.проверить
        аргументы_H = (исполнитель, H, запись, запись['наблюдения']['события'], попытки['события'],
            база, области['события'], ветка_H, ожидания[H['задача']])
    else:
        функция_H = сохранённый_писатель.проверить
        аргументы_H = (исполнитель, H, запись['наблюдения']['события'], попытки['события'],
            база, области['события'], ветка_H, ожидания[H['задача']], True)
    аргументы_S = (исполнитель, S, база, попытки['сообщения']['аргументы']['prompt'], ожидания[S['задача']])
    профиль_S = {'модель': попытки['сообщения']['аргументы']['model'], 'усилие': попытки['сообщения']['аргументы']['thinking']}
    результаты = {'события': функция_H(*аргументы_H),
        'сообщения': остановка_ребёнка.проверить(*аргументы_S, **профиль_S)}
    результаты['сообщения'] = {'вид': S['вид'], 'попытка': S['попытка'], 'вызов': вызовы[1]['источник'],
        'остановка': результаты['сообщения']}
    возобновления_до_записи.проверить(исполнитель, вход, нативный, попытки)
    хранение.требовать(_ветки(исполнитель, вход, план, состояние) == координатор
        and _история(исполнитель, состояние, вход['запуск']) == история, 'Основания сдвинулись при чтении')
    квитанция = {'схема': терминал_запуска.СХЕМА_СМЕШАННОГО_СОЗДАНИЯ, 'запуск': вход['запуск'],
        'план_sha256': план['sha256'], 'вход_sha256': хранение.хэш(вход), 'история_sha256': история,
        'координатор': координатор, 'слои': результаты, 'источник': нативный['источник'], 'возобновления': {},
        'ожидания': {з: {к: о[к] for к in ('id', 'источник', 'интервал')} for з, о in ожидания.items()},
        'свидетельство_координатора': аттестация, 'отсутствие_незаписанного_вызова_доказано': False}
    return {**квитанция, 'sha256': хранение.хэш(квитанция)}, [(функция_H, аргументы_H), (остановка_ребёнка.проверить, аргументы_S, профиль_S)]


def предпросмотр(исполнитель, вход):
    return _план(исполнитель, вход, исполнитель.хранилище.прочитать())[0]


def завершить(исполнитель, вход, ожидаемый_sha256):
    with исполнитель.хранилище.изменить() as состояние:
        результат, сверки = _план(исполнитель, вход, состояние)
        хранение.требовать(результат['sha256'] == ожидаемый_sha256, 'Изменён просмотренный смешанный переход')
        ключ = терминал_запуска.ключ(вход['запуск'])
        if ключ not in состояние['приёмы']:
            функция_H, аргументы_H = сверки[0]
            функция_S, аргументы_S, профиль_S = сверки[1]
            хранение.требовать(функция_H(*аргументы_H) == результат['слои']['события']
                and функция_S(*аргументы_S, **профиль_S) == результат['слои']['сообщения']['остановка'],
                'Остановленный ребёнок сдвинулся перед терминалом')
            _снимок_корня(вход['источник'])
            план = исполнитель._прочитать(состояние, вход['запуск'])['план']
            хранение.требовать(_ветки(исполнитель, вход, план, состояние) == результат['координатор']
                and _история(исполнитель, состояние, вход['запуск']) == результат['история_sha256'],
                'Ветки или история сдвинулись перед терминалом')
            исполнитель.хранилище.проверить_владельца_под_замком(состояние,
                ожидаемый_коммит=вход['координатор']['HEAD'], ожидаемая_ветка=вход['координатор']['ref'])
            состояние['приёмы'][ключ] = результат
        return copy.deepcopy(результат)

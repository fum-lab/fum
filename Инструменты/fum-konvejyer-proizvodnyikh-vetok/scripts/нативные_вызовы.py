"""Чтение настоящих create_thread из ограниченного неизменяемого снимка JSONL."""
import hashlib
import os
from pathlib import Path

import приём_направления as хранение

ПРЕДЕЛ_СТРОКИ = 16 * 1024 * 1024


def прочитать(вход, задача, *, аргументы=None, ожидания=()):
    хранение.поля(вход, {"путь", "начало", "начало_sha256", "граница", "sha256"})
    хранение.требовать(хранение.идентификатор_задачи(задача), "Нужен нативный UUID корня")
    хранение.требовать(аргументы is None or type(аргументы) is list and аргументы
                       and all(type(а) is dict and а for а in аргументы), "Нужны точные аргументы отбора")
    хранение.требовать(all(хранение.идентификатор_задачи(з) for з in ожидания), "Нужны UUID ожидаемых задач")
    ожидаемые_аргументы = аргументы
    начало, граница = вход["начало"], вход["граница"]
    хранение.требовать(type(начало) is int and type(граница) is int and 0 < начало <= граница,
                       "Неверные границы снимка")
    хранение.требовать(all(хранение.шестнадцатеричный(вход[к]) for к in ("начало_sha256", "sha256")),
                       "Нужны хэши обоих префиксов")
    хранение.требовать(type(вход["путь"]) is str and Path(вход["путь"]).is_absolute(), "Нужен абсолютный источник")
    путь = Path(вход["путь"])
    хранение.безопасный_путь(путь)
    полный, прежний = hashlib.sha256(), hashlib.sha256()
    вызовы, ответы_ожидания, возобновления = [], [], []
    начатые, завершённые, выбранные, дубли = {}, set(), set(), set()
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
        до = os.fstat(поток.fileno())
        хранение.требовать(до.st_size == граница, "Нужен точный завершённый снимок источника")
        первая = поток.readline(ПРЕДЕЛ_СТРОКИ + 1)
        хранение.требовать(первая.endswith(b"\n") and len(первая) <= min(начало, ПРЕДЕЛ_СТРОКИ),
                           "Нет завершённого начала источника")
        мета = хранение.разобрать(первая)
        хранение.требовать(type(мета) is dict and мета.get("type") == "session_meta"
                           and type(мета.get("payload")) is dict and мета["payload"].get("id") == задача,
                           "Нативный UUID источника не совпал")
        полный.update(первая)
        прежний.update(первая)
        последний = первая[-1:]
        while поток.tell() < начало:
            блок = поток.read(min(4 * 1024 * 1024, начало - поток.tell()))
            хранение.требовать(bool(блок), "Оборван прежний префикс")
            полный.update(блок)
            прежний.update(блок)
            последний = блок[-1:]
        хранение.требовать(последний == b"\n" and прежний.hexdigest() == вход["начало_sha256"],
                           "Изменён прежний префикс либо граница строки")
        while поток.tell() < граница:
            позиция = поток.tell()
            строка = поток.readline(min(ПРЕДЕЛ_СТРОКИ, граница - позиция) + 1)
            хранение.требовать(строка.endswith(b"\n") and len(строка) <= ПРЕДЕЛ_СТРОКИ
                               and поток.tell() <= граница, "Нет ограниченной завершённой строки JSONL")
            полный.update(строка)
            запись = хранение.разобрать(строка)
            хранение.требовать(type(запись) is dict, "Неверная запись JSONL")
            данные = запись.get("payload", {})
            if запись.get("type") != "event_msg" or type(данные) is not dict:
                continue
            элемент = данные.get("item", {})
            if (type(элемент) is not dict or элемент.get("type") != "McpToolCall"
                    or элемент.get("server") != "codex_app"):
                continue
            вид, номер, аргументы = данные.get("type"), элемент.get("id"), элемент.get("arguments")
            инструмент = элемент.get("tool")
            выбран = инструмент == "create_thread" and (ожидаемые_аргументы is None or аргументы in ожидаемые_аргументы)
            if инструмент == "wait_threads" and ожидания:
                цели = аргументы.get("targets") if type(аргументы) is dict else None
                хранение.требовать(type(цели) is list and all(type(ц) is dict for ц in цели), "Неизвестный отбор ожидания")
                выбран = bool(set(ожидания).intersection(ц.get("threadId") for ц in цели))
            if инструмент in {"send_message_to_thread", "handoff_thread"} and type(аргументы) is dict:
                выбран = аргументы.get("threadId") in ожидания
            хранение.требовать(хранение.текст(номер), "Нет идентичности вызова")
            сигнатура = хранение.хэш({"инструмент": инструмент, "аргументы": аргументы})
            if выбран:
                выбранные.add(номер)
            if номер in выбранные:
                хранение.требовать(type(аргументы) is dict and аргументы, "Нет аргументов вызова")
                хранение.требовать(данные.get("thread_id") == задача, "Чужой UUID в первичном MCP-событии")
                хранение.требовать(вид in {"item_started", "item_completed"}, "Неизвестная фаза MCP-вызова")
            if вид == "item_started":
                if номер in начатые or номер in завершённые:
                    дубли.add(номер)
                хранение.требовать(номер not in выбранные or номер not in дубли, "Повтор начала MCP-вызова")
                начатые.setdefault(номер, сигнатура)
                continue
            if вид != "item_completed":
                continue
            if номер in завершённые:
                дубли.add(номер)
            завершённые.add(номер)
            if номер not in выбранные:
                continue
            хранение.требовать(номер not in дубли, "Повтор завершения MCP-вызова")
            хранение.требовать(номер not in начатые or начатые[номер] == сигнатура, "Изменены аргументы начатого вызова")
            ответ = элемент.get("result")
            хранение.требовать(элемент.get("status") == "completed" and type(ответ) is dict
                               and ответ.get("isError") is False and type(ответ.get("content")) is list,
                               "Неизвестный либо неуспешный исход MCP-вызова")
            приёмник = вызовы if инструмент == "create_thread" else ответы_ожидания if инструмент == "wait_threads" else возобновления
            приёмник.append({"id": номер, "аргументы": аргументы, "ответ": ответ,
                             "источник": {"начало": позиция, "конец": поток.tell(),
                                          "sha256": hashlib.sha256(строка).hexdigest()}})
        после = путь.stat()
        хранение.требовать((до.st_dev, до.st_ino, до.st_size, до.st_mtime_ns)
                           == (после.st_dev, после.st_ino, после.st_size, после.st_mtime_ns),
                           "Снимок изменился при чтении")
    хранение.требовать(полный.hexdigest() == вход["sha256"], "Подменён полный снимок")
    хранение.требовать(not выбранные - завершённые, "Незавершённый MCP-вызов")
    return {"схема": "fum.наблюдённые-вызовы-запуска.1", "задача": задача,
            "источник": {к: в for к, в in вход.items() if к != "путь"}, "вызовы": вызовы,
            "ожидания": ответы_ожидания, "возобновления": возобновления,
            "начальная_граница": len(первая),
            "отсутствие_незаписанного_вызова_доказано": False}

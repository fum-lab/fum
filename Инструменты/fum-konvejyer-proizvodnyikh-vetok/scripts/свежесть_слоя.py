"""План свежести своей области без обхода и записи общего индекса."""
import hashlib
import importlib
from pathlib import Path, PurePosixPath
import sys

import дочернее_назначение
import запись_слоя
import приём_направления as хранение
import снимок_области

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-svezhestj-markdown/scripts'))
свежесть = importlib.import_module('update-md-recency')
КОД = {Path(имя).resolve(): hashlib.sha256(Path(имя).read_bytes()).hexdigest()
       for имя in (__file__, свежесть.__file__, свежесть.ограды_цитат.__file__, свежесть.маска_архива.__file__)}


def проверить_код():
    for путь, отпечаток in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == отпечаток,
                           'Код свежести изменён после загрузки')


def markdown(корень, назначение):
    данные = хранение.гит(корень, 'ls-files', '--cached', '--others', '--exclude-standard', '-z', '--',
                          *(':(literal)' + имя for имя in назначение['каталоги']), сырые=True)
    имена = sorted({э.decode('utf-8') for э in данные.split(b'\0') if э and э.endswith(b'.md')})
    for имя in имена:
        хранение.требовать(any(имя.startswith(п) for п in назначение['каталоги']), 'Markdown вне собственной области')
    return [снимок_области.охват.точный_путь(Path(корень), имя) for имя in имена]


def подготовить(корень, задача, источник):
    проверить_код()
    корень = Path(корень)
    назначение = дочернее_назначение.прочитать(корень, задача, источник)
    время = свежесть.format_msk(свежесть.parse_now())
    файлы, прежние, входы = [], {}, {}
    for путь in markdown(корень, назначение):
        имя = путь.relative_to(корень).as_posix()
        до = снимок_области.охват.состояние_пути(путь)
        входы[имя] = до
        if not путь.exists():
            continue
        хранение.безопасный_путь(путь)
        текст = свежесть.read_text(путь)
        _, метка, _ = свежесть.split_recency_block(текст, путь=путь, корень=корень)
        if метка is not None:
            хранение.требовать(свежесть.DISPLAY_TIME_RE.fullmatch(метка.timestamp) is not None,
                               'Неверный формат времени свежести: ' + имя)
            свежесть.parse_display_time(метка.timestamp)
        запись, ошибки, изменён = свежесть.process_markdown_file(путь, корень, {имя}, время, True, False)
        допустимые = {'missing recency metadata: ' + имя, 'stale recency metadata: ' + имя}
        хранение.требовать(not (set(ошибки) - допустимые), '; '.join(ошибки))
        хранение.требовать(снимок_области.охват.состояние_пути(путь) == до, 'Markdown сдвинулся при чтении')
        if изменён:
            содержание, _, _ = свежесть.split_recency_block(текст, путь=путь, корень=корень)
            новое = свежесть.attach_recency_block(свежесть.canonical_content(содержание), запись.timestamp, запись.digest)
            файлы.append(запись_слоя.каркас.PreparedFile(PurePosixPath(имя), новое.encode('utf-8'), до['режим']))
            прежние[имя] = до
    хранение.требовать(дочернее_назначение.прочитать(корень, задача, источник) == назначение,
                       'Назначение сдвинулось при подготовке свежести')
    запись_слоя.сверить_входы(корень, назначение, входы)
    проверить_код()
    return {'назначение_sha256': назначение['sha256'], 'файлы': файлы, 'прежние': прежние, 'входы': входы}


def применить(корень, задача, источник, план):
    проверить_код()
    хранение.требовать(isinstance(план, dict) and set(план) == {'назначение_sha256', 'файлы', 'прежние', 'входы'},
                       'Неверный план собственной свежести')
    return запись_слоя.установить(корень, задача, источник, план['файлы'], план['назначение_sha256'],
                                 ожидаемые=план['прежние'], входы=план['входы'])

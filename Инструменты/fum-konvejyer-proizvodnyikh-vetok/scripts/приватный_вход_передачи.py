"""Вычислить приватные адреса v3 из собственного проверенного назначения."""
import os
from pathlib import Path

import дочернее_назначение
import дочерний_коммит
import снимок_нативного_источника as снимок
import создание_коммита as коммит
import полный_поток_передачи

файлы = снимок.файлы
хранение = снимок.хранение
ПОЛЯ = {'имя_автора', 'заголовок', 'описание', 'разрешённые_цели'}


def прочитать(каталог, *, живой=True):
    каталог = файлы._место(каталог)
    файлы._приватный(каталог, каталог=True)
    параметры = хранение.разобрать(файлы._читать(каталог / 'вход.json'))
    описание = хранение.разобрать(файлы._читать(каталог / 'пакет.json'))
    хранение.поля(описание, {'схема', 'задача', 'вход_sha256', 'снимок_sha256'})
    задача = os.environ.get('CODEX_THREAD_ID')
    хранение.требовать(описание['схема'] == 'fum.приватный-вход-передачи.1'
        and описание['задача'] == задача == параметры['исполнитель']
        and описание['вход_sha256'] == хранение.хэш(параметры), 'Чужой либо изменённый вход передачи')
    исходник = снимок.прочитать(каталог / 'нативный', задача, живой=False)
    хранение.требовать(описание['снимок_sha256'] == хранение.хэш(исходник)
        and параметры['источник_модели'] == str(каталог / 'нативный/источник.jsonl'),
        'Подменён источник подготовленного входа')
    if живой:
        снимок.наблюдать(каталог / 'нативный', задача, каталог / 'наблюдение.json')
    return параметры


def создать_вход(корень, источник, каталог, поля):
    хранение.поля(поля, ПОЛЯ)
    корень, источник = Path(корень), Path(источник)
    каталог = файлы._место(каталог)
    задача = os.environ.get('CODEX_THREAD_ID')
    if каталог.exists():
        прежний = прочитать(каталог)
        исходник = снимок.прочитать(каталог / 'нативный', задача)
        хранение.требовать(прежний['корень'] == str(корень) and исходник['источник'] == str(источник)
            and all(прежний[к] == поля[к] for к in ПОЛЯ), 'Параметры существующей передачи изменены')
        return прежний
    назначение = дочернее_назначение.прочитать(корень, задача, источник)
    каталог.mkdir(mode=0o700)
    описание = снимок.создать(источник, задача, каталог / 'нативный')
    журнал = назначение['каталоги'][1]
    параметры = {'схема': 'fum.создание-коммита.3', 'режим': 'дочерняя-передача',
        'корень': str(корень), 'ветка': назначение['писатель']['ref'],
        'исходный_коммит': назначение['база'], 'родители': [назначение['база']],
        'задача': назначение['корневая_задача'], 'исполнитель': задача,
        'назначение_sha256': хранение.хэш(дочернее_назначение.привязка(назначение)),
        'запрос': журнал + 'запрос.md', 'источники': [],
        'история_модели': журнал + 'материалы/история-модели.json',
        'источник_модели': str(каталог / 'нативный/источник.jsonl'),
        **{ключ: str(каталог / имя) for ключ, имя in (
            ('кэш_модели', 'курсор-модели.json'), ('сообщение', 'сообщение.txt'),
            ('подготовка', 'подготовка.json'), ('квитанция', 'квитанция.json'))}, **поля}
    дочерний_коммит.первичные(параметры)
    сырые = файлы._читать(каталог / 'нативный/источник.jsonl')
    полный_поток_передачи.проверить(сырые, назначение['источник']['граница'])
    файлы._записать(каталог / 'вход.json', хранение.байты(параметры))
    снимок.наблюдать(каталог / 'нативный', задача, каталог / 'наблюдение.json', первое=True)
    пакет = {'схема': 'fum.приватный-вход-передачи.1', 'задача': задача,
        'вход_sha256': хранение.хэш(параметры), 'снимок_sha256': хранение.хэш(описание)}
    файлы._записать(каталог / 'пакет.json', хранение.байты(пакет))
    хранение.синхронизировать_каталог(каталог)
    хранение.синхронизировать_каталог(каталог.parent)
    хранение.требовать(прочитать(каталог) == параметры, 'Изменился сохранённый вход передачи')
    return параметры


def выполнить_фазу(каталог, фаза, проверки=(), предел=600):
    параметры = прочитать(каталог, живой=False)
    хранение.требовать(фаза in {'подготовить', 'готово', 'создать'}, 'Неизвестная фаза передачи')
    подготовка = Path(параметры['подготовка'])
    if фаза != 'подготовить':
        сохранённая = хранение.разобрать(коммит.прочитать(подготовка, приватный=True))
        хранение.требовать(сохранённая.get('параметры') == параметры, 'Подготовка принадлежит другому пакету')
    восстановление = фаза == 'создать' and os.path.lexists(параметры['квитанция'])
    if not восстановление:
        прочитать(каталог)
    if фаза == 'подготовить':
        результат = коммит.подготовить(параметры)
    elif фаза == 'готово':
        результат = коммит.объявить_готовность(подготовка, list(проверки), предел, {})
    else:
        результат = коммит.создать(подготовка, list(проверки))
    # Наблюдение после действия не отменяет его результат и не повторяет эффект.
    # Для уже созданной квитанции живой источник может быть недоступен.
    try:
        прочитать(каталог)
        после = {'состояние': 'проверено', 'новые_действия_разрешены': True}
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as ошибка:
        после = {'состояние': 'нужен разбор', 'причина': str(ошибка), 'новые_действия_разрешены': False}
    return {'схема': 'fum.фаза-приватной-передачи.1', 'фаза': фаза,
        'восстановление': восстановление, 'результат': результат, 'наблюдение_после': после}

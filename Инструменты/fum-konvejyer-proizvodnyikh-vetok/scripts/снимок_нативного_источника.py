"""Неизменяемые исходные байты и сверка живого хвоста перед новым действием."""
import hashlib
import io
import os
from pathlib import Path
import stat
import sys

import хранилище_незавершённого as файлы

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-svyaznostj-rabochej-sessii/scripts'))
import история_модели
import сообщения_задачи

хранение = файлы.хранение
ПРЕДЕЛ = 16 * 1024 * 1024
ТРАНСПОРТЫ = {'create_thread', 'send_message_to_thread', 'handoff_thread'}


def _сырой(путь):
    путь = Path(путь)
    хранение.требовать(путь.is_absolute() and путь == путь.resolve(), 'Нужен физический адрес native JSONL')
    хранение.безопасный_путь(путь)
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        хранение.требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1 and 0 < до.st_size <= ПРЕДЕЛ,
            'Нужен ограниченный обычный native JSONL без жёстких ссылок')
        сырые = поток.read(ПРЕДЕЛ + 1)
        после = путь.stat()
        метка = lambda с: (с.st_dev, с.st_ino, с.st_size, с.st_mtime_ns, с.st_ctime_ns)
        хранение.требовать(метка(до) == метка(после) == метка(os.fstat(поток.fileno())),
            'Нативный источник изменился при чтении')
    хранение.требовать(len(сырые) == до.st_size and сырые.endswith(b'\n'), 'Оборван нативный источник')
    return сырые, [до.st_dev, до.st_ino]


def _модель(сырые, задача):
    данные = история_модели._приём(io.BytesIO(сырые), задача, None, len(сырые),
        {'прочитано_байтов': 0, 'разобрано_строк': 0})
    хранение.требовать(not данные['пропуски'] and not данные['неполный_хвост']
        and данные['последнее'] is not None, 'Нет полного наблюдения модели в снимке')
    return данные


def проверить_хвост(сырые):
    """Неизвестное событие требует нового разбора; имя транспорта важнее tool-типа."""
    for строка in сырые.splitlines(keepends=True):
        запись = хранение.разобрать(строка)
        хранение.требовать(type(запись) is dict, 'Неизвестная запись native JSONL')
        данные = запись.get('payload', {})
        хранение.требовать(type(данные) is dict, 'Неизвестный payload native JSONL')
        тип, вид = запись.get('type'), данные.get('type')
        допустимо = тип == 'token_usage_record'
        if тип == 'event_msg':
            допустимо = вид in {'token_count', 'agent_message', 'agent_reasoning'}
            if вид == 'item_completed':
                элемент = данные.get('item')
                допустимо = (type(элемент) is dict and элемент.get('type') in {
                    'AgentMessage', 'CommandExecution', 'Reasoning', 'McpToolCall',
                    'FunctionCall', 'FunctionCallOutput'}
                    and элемент.get('name') not in ТРАНСПОРТЫ)
        elif тип == 'response_item':
            допустимо = (вид == 'message' and данные.get('role') == 'assistant'
                or вид in {'reasoning', 'function_call', 'custom_tool_call',
                           'function_call_output', 'custom_tool_call_output'}
                and данные.get('name') not in ТРАНСПОРТЫ)
        хранение.требовать(допустимо,
            'После снимка получено новое управляющее или неизвестное событие; нужна новая подготовка')


def прочитать(каталог, задача, *, живой=True):
    каталог = файлы._место(каталог)
    файлы._приватный(каталог, каталог=True)
    хранение.требовать({п.name for п in каталог.iterdir()} == {'источник.jsonl', 'описание.json'},
        'Неполный состав нативного снимка')
    описание = хранение.разобрать(файлы._читать(каталог / 'описание.json'))
    хранение.поля(описание, {'схема', 'задача', 'источник', 'идентичность', 'граница', 'sha256'})
    хранение.требовать(описание['схема'] == 'fum.снимок-нативного-источника.1'
        and описание['задача'] == задача, 'Чужой нативный снимок')
    сырые = файлы._читать(каталог / 'источник.jsonl')
    хранение.требовать(0 < len(сырые) == описание['граница'] <= ПРЕДЕЛ and сырые.endswith(b'\n')
        and hashlib.sha256(сырые).hexdigest() == описание['sha256'], 'Изменён нативный снимок')
    _модель(сырые, задача)
    if живой:
        текущие, идентичность = _сырой(описание['источник'])
        хранение.требовать(идентичность == описание['идентичность'], 'Живой источник заменён')
        хранение.требовать(текущие.startswith(сырые), 'Префикс живого источника изменён или усечён')
        проверить_хвост(текущие[len(сырые):])
    return описание


def создать(источник, задача, каталог):
    каталог = файлы._место(каталог)
    if каталог.exists():
        описание = прочитать(каталог, задача)
        хранение.требовать(описание['источник'] == str(источник), 'Источник существующего снимка изменён')
        return описание
    сырые, идентичность = _сырой(источник)
    _модель(сырые, задача)
    описание = {'схема': 'fum.снимок-нативного-источника.1', 'задача': задача,
        'источник': str(источник), 'идентичность': идентичность,
        'граница': len(сырые), 'sha256': hashlib.sha256(сырые).hexdigest()}
    каталог.mkdir(mode=0o700)
    файлы._записать(каталог / 'источник.jsonl', сырые)
    # Описание устанавливается последним; оборванная запись не становится входом.
    файлы._записать(каталог / 'описание.json', хранение.байты(описание))
    хранение.синхронизировать_каталог(каталог)
    хранение.синхронизировать_каталог(каталог.parent)
    хранение.требовать(прочитать(каталог, задача) == описание, 'Изменился сохранённый снимок')
    return описание


def наблюдать(каталог, задача, курсор, *, первое=False):
    """Не терять уже увиденный нейтральный хвост между фазами передачи."""
    каталог, курсор = Path(каталог), Path(курсор)
    описание = прочитать(каталог, задача, живой=False)
    хранение.требовать(курсор.parent == каталог.parent and курсор.name == 'наблюдение.json',
        'Неверный адрес курсора наблюдения')
    хранение.безопасный_путь(курсор)
    with сообщения_задачи._замок(курсор):
        хранение.безопасный_путь(курсор)
        хранение.требовать(курсор.exists() != первое,
            'Курсор наблюдения потерян либо уже установлен')
        сырые, идентичность = _сырой(описание['источник'])
        граница = описание['граница']
        хранение.требовать(идентичность == описание['идентичность'] and len(сырые) >= граница
            and hashlib.sha256(сырые[:граница]).hexdigest() == описание['sha256'],
            'Живой источник заменён, усечён или изменён')
        if курсор.exists():
            прежнее = хранение.разобрать(история_модели._прочитать(курсор, приватный=True))
            хранение.поля(прежнее, {'снимок_sha256', 'граница', 'sha256', 'отказ'})
            хранение.требовать(прежнее['отказ'] is None,
                'Ранее наблюдалось новое управление; передача остаётся закрытой')
            хранение.требовать(прежнее['снимок_sha256'] == хранение.хэш(описание)
                and type(прежнее['граница']) is int and граница <= прежнее['граница'] <= len(сырые)
                and hashlib.sha256(сырые[:прежнее['граница']]).hexdigest() == прежнее['sha256'],
                'Изменён ранее наблюдённый хвост')
        новое = {'снимок_sha256': хранение.хэш(описание), 'граница': len(сырые),
                 'sha256': hashlib.sha256(сырые).hexdigest(), 'отказ': None}
        try:
            проверить_хвост(сырые[граница:])
        except (ValueError, KeyError, TypeError) as ошибка:
            новое['отказ'] = str(ошибка)
            сообщения_задачи._установить(курсор, хранение.байты(новое))
            raise
        сообщения_задачи._установить(курсор, хранение.байты(новое))
    return новое

"""Подготовить приём по нативному поручению; повтор восстанавливает тот же эпизод."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import time

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import вход_приёма
import эпизод_приёма as эпизод
import приём_интеграции
import слияние_приёма
import журнал_приёма
import коммит_приёма
import создание_коммита as коммит

хранение = эпизод.хранение
КОД = {**журнал_приёма.КОД, **{Path(м.__file__).resolve(): м.КОД_ПРИ_ЗАГРУЗКЕ
    for м in (вход_приёма, коммит_приёма, коммит, коммит.готовность)}}
КОД[Path(__file__).resolve()] = КОД_ПРИ_ЗАГРУЗКЕ


def подготовить(файл):
    начало = time.monotonic_ns(); профиль = []
    def измерить(стадия, действие):
        старт = time.monotonic_ns(); исход = 'отказ'
        try:
            результат = действие(); исход = 'успех'
            return результат
        finally:
            профиль.append({'стадия': стадия, 'исход': исход,
                'длительность_наносекунды': time.monotonic_ns() - старт})
    корень = Path.cwd().resolve()
    данные, блок = вход_приёма.прочитать(файл, корень)
    # Данные из JSON никогда не становятся callback либо готовым основанием.
    def перечитать():
        return приём_интеграции.прочитать(корень, блок['исполнитель'], данные['источник'],
            данные['план'], данные['свидетельство'], данные['текст'])
    прежнее = эпизод.найти(блок['исполнитель'], блок['назначение_sha256'])
    основание = прежнее['основание'] if прежнее is not None else измерить('первичный допуск', перечитать)
    хранение.требовать(основание['поручение'] == блок, 'Изменено поручение того же эпизода')
    измерить('код из базы C', lambda: приём_интеграции.проверить_код(корень, блок['база'], дополнительный_код=КОД))
    параметры = вход_приёма.параметры(данные, основание)
    коммит_приёма.адрес(параметры)
    путь = эпизод.путь_эпизода(основание); вход = путь.with_suffix('.вход-коммита.json')
    эпизод.проверить_каталоги(путь)
    хранение.создать_каталоги(путь.parent, Path(путь.anchor), права=0o700)
    эпизод.проверить_каталоги(путь)
    with эпизод.файлы._замок(путь.with_suffix('.публичный.json')):
        if os.path.lexists(вход):
            хранение.требовать(эпизод.прочитать_файл(вход) == параметры,
                'Изменены сохранённые параметры приёма')
        else:
            хранение.требовать(эпизод.прочитать(основание) is None,
                'Потерян вход уже начатого приёма')
            хранение.установить(вход, хранение.байты(параметры))
        квитанция = Path(параметры['квитанция'])
        if os.path.lexists(квитанция):
            # Наличие квитанции обязательно: этот маршрут не создаёт первый R.
            подготовка = Path(параметры['подготовка'])
            сохранённая = хранение.разобрать(коммит.прочитать(подготовка, приватный=True))
            хранение.требовать(сохранённая.get('параметры') == параметры,
                'Подготовка принадлежит другому входу приёма')
            результат = измерить('восстановление R', lambda: коммит.создать(подготовка, [блок['проверка']]))
            состояние = 'коммит-восстановлен'
        else:
            if прежнее is not None:
                хранение.требовать(измерить('повторный нативный допуск', перечитать) == основание,
                    'Сдвинулся допуск приёма')
            слияние = слияние_приёма.СлияниеПриёма(основание, данные['план'], данные['реестр'], перечитать)
            журнал = журнал_приёма.ЖурналПриёма(слияние)
            if not os.path.lexists(журнал.путь):
                измерить('слияние или его восстановление', слияние.применить)
            # После начала J его разрешённые правки проверяет именно этот слой.
            измерить('установка или чтение J', журнал.установить)
            результат = None; состояние = 'журнал-установлен'
    return {'схема': 'fum.подготовленный-дочерний-приём.1', 'состояние': состояние,
        'вход_коммита': str(вход), 'подготовка': параметры['подготовка'], 'результат': результат,
        'профиль': профиль, 'длительность_наносекунды': time.monotonic_ns() - начало}


def главная(аргументы=None):
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--вход', type=Path, required=True)
    вход = парсер.parse_args(аргументы)
    try:
        результат = подготовить(вход.вход)
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as ошибка:
        print(json.dumps({'схема': 'fum.отказ-входа-приёма.1', 'ошибка': str(ошибка),
            'повтор_эффекта_разрешён': False}, ensure_ascii=False))
        return 2
    print(json.dumps(результат, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(главная())

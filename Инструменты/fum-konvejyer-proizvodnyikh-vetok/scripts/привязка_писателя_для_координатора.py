"""Первоначальное назначение ребёнка читается корнем без смены Native UUID."""
import os

import приём_направления as хранение
import постановка_задачи as постановка
import дочернее_назначение
import нативное_назначение
import поручение_слоя


def проверить(исполнитель, запись, слой, попытка, наблюдение, источник, каталоги, ветка):
    """Возвращает прежнюю привязку, без дочернего допуска или разрешения записи."""
    хранение.требовать(os.environ.get('CODEX_THREAD_ID') == исполнитель.задача,
                       'Нативный UUID не совпадает с читающим координатором')
    база = запись['план']['координатор']['HEAD']
    хранение.требовать(слой in запись['наблюдения'] and запись['наблюдения'][слой] == наблюдение
        and type(наблюдение) is dict and наблюдение['задача'] != исполнитель.задача
        and попытка['аргументы'] == запись['план']['аргументы'][слой] and попытка['база'] == база,
        'Не подтверждено первоначальное назначение наблюдённого ребёнка')
    поручение = нативное_назначение.прочитать(источник['путь'])
    хранение.требовать(поручение['назначение'] == поручение_слоя.блок(запись['смысл'], слой)
        and поручение['текст'] == попытка['аргументы']['prompt'],
        'Блок назначения или полный текст расходится с коммитом C')
    def первичное():
        раннее = постановка.прочитать_подтверждение(
            наблюдение['корень'], наблюдение['задача'], база, источник['путь'])
        хранение.требовать(раннее['схема'] == 'fum.начальная-база-задачи.2'
            and раннее['ref'] == ветка and (раннее['модель'], раннее['рассуждение']) ==
                (попытка['аргументы']['model'], попытка['аргументы']['thinking']),
            'Изменилось первоначальное подтверждение модели или ветки')
        return {**раннее, 'поручение': постановка.проверить_нативное_поручение(
            источник['путь'], исполнитель.задача, попытка['аргументы']['prompt'], кодирование='xml-v1')}
    хранение.требовать(первичное() == наблюдение, 'Первоначальное наблюдение ребёнка подменено')
    основание = {'корневая_задача': исполнитель.задача, 'база': база, 'слой': слой,
        'назначение': поручение['назначение'], 'каталоги': каталоги,
        'источник': поручение['источник'],
        'раннее_sha256': хранение.хэш({к: в for к, в in наблюдение.items() if к != 'поручение'}),
        'писатель': {'задача': наблюдение['задача'], 'путь': наблюдение['корень'], 'ref': ветка}}
    хранение.требовать(нативное_назначение.прочитать(источник['путь']) == поручение
        and первичное() == наблюдение, 'Назначение изменилось при чтении координатором')
    return дочернее_назначение.привязка(основание), поручение

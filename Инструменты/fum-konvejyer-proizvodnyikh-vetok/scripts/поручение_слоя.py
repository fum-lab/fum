"""Канонический текст нативного поручения; байты версии v1 сохранены."""
import приём_направления as хранение

НАЧАЛО = "<fum_layer_assignment>\n"
КОНЕЦ = "</fum_layer_assignment>\n"


def сформировать(текст, слой, коммит, назначение=None):
    имя = слой["слой"]
    подтверждение = "подтвердить-начало --с-поручением" if назначение is not None else "подтвердить-начало"
    текст += "\n\nСлой «" + имя + "», каталог «" + слой["каталог"] + "». Коммит постановки: " + коммит + ".\n"
    текст += ("До содержательной записи прочитай правила и проверь собственные физический корень, HEAD и полный ref. "
              "При чистом detached HEAD на коммите постановки создай свободную собственную ветку " + слой["ветка"].removeprefix("refs/heads/")
              + " от того же OID; чужие refs не меняй. Затем выполни python3 -B Инструменты/fum-reyestr-planirovaniya/scripts/принять-направление.py "
              "--корень-репозитория . --задача <свой настоящий UUID> " + подтверждение + " --источник <свой первичный JSONL> --коммит " + коммит
              + ". При несовпадении останови запись и сообщи наблюдение. "
              "Сообщи фактические UUID, корень, ref, начальный HEAD и наблюдённую модель. Общие индексы и чужие каталоги не изменяй.\n")
    if назначение is not None:
        хранение.требовать("<fum_layer_assignment>" not in текст and "</fum_layer_assignment>" not in текст,
                           "Поручение содержит повторный блок назначения")
        текст += НАЧАЛО + хранение.байты(назначение).decode("utf-8") + КОНЕЦ
    return текст


def блок(пакет, слой):
    return {"схема": "fum.первоначальное-назначение-слоя.1", "корневая_задача": пакет["задача"],
            "база": пакет["постановка"]["коммит"], "файлы": пакет["постановка"]["файлы"],
            "план": пакет["план"], "слой": слой, "назначение": пакет["назначение"]}

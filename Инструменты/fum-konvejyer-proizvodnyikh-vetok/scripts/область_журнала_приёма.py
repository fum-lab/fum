"""Проверить границу S плюс конечные пути J, не меняя индекс и общие файлы."""
import hashlib
import os
from pathlib import Path
import stat
import unicodedata

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import доставка_гит as гит
import доставка_отчёта
import эпизод_приёма as эпизод
import файл_журнала_приёма

хранение = эпизод.хранение


def сравнимое(имя):
    return unicodedata.normalize('NFC', имя).casefold()


def проверить_путь(корень, относительный):
    путь = корень
    for часть in Path(относительный).parts:
        if путь.exists():
            хранение.безопасный_путь(путь, каталог=True)
            совпадения = [п.name for п in путь.iterdir() if сравнимое(п.name) == сравнимое(часть)]
            хранение.требовать(not совпадения or совпадения == [часть], 'Регистровая или Unicode-коллизия Журнала')
        путь /= часть
        хранение.требовать(not путь.is_symlink(), 'Ссылка в пути Журнала')
    return путь


def файлы(корень, план, установлено):
    журнал = проверить_путь(корень, план['журнал'])
    допустимые = set(план['будущие_пути'] if установлено else
        [з[ключ] for з in план['файлы'] for ключ in ('путь', 'временный')])
    каталоги = {план['журнал'].removesuffix('/')}
    for имя in допустимые:
        каталоги.update(п.as_posix() for п in Path(имя).parents if п.as_posix().startswith(план['журнал']))
    if журнал.exists():
        хранение.безопасный_путь(журнал, каталог=True)
        for путь in журнал.rglob('*'):
            имя = путь.relative_to(корень).as_posix()
            проверить_путь(корень, имя)
            if путь.is_dir():
                хранение.требовать(имя in каталоги, 'Лишний каталог в новой паре')
            else:
                хранение.требовать(имя in допустимые, 'Лишний файл в новой паре')
                хранение.безопасный_путь(путь)
    for запись in план['файлы']:
        путь = проверить_путь(корень, запись['путь'])
        временный = проверить_путь(корень, запись['временный'])
        if os.path.lexists(временный):
            хранение.требовать(not установлено and not os.path.lexists(путь),
                'Временный файл появился рядом с готовым результатом')
            файл_журнала_приёма.проверить(временный, запись['текст'].encode('utf-8'))
        if not os.path.lexists(путь):
            хранение.требовать(not установлено, 'Потерян файл установленного Журнала')
            continue
        хранение.безопасный_путь(путь)
        хранение.требовать(stat.S_IMODE(путь.stat().st_mode) == запись['режим'], 'Изменён режим пары')
        if not установлено:
            хранение.требовать(путь.read_bytes() == запись['текст'].encode('utf-8'), 'Изменены байты незавершённой пары')
    for имя in план['будущие_пути']:
        # Проверяются и будущие отсутствующие пути: собственный файл нельзя
        # незаметно оставить игнорируемым вместо включения в конечный состав.
        результат = гит.выполнить(корень, 'check-ignore', '--no-index', '--', имя, допустимые=(0, 1))
        хранение.требовать(результат.returncode == 1, 'Путь новой пары игнорируется Git')


def слияние(доставка, основание, квитанция, допустимые, установлено):
    корень = доставка.корень
    наблюдение = доставка._владелец()
    хранение.требовать(квитанция is not None and квитанция['стадия'] == 'применено'
        and квитанция['план'] == доставка.план['идентификатор']
        and квитанция['дерево'] == основание['дерево'] and квитанция.get('отчёт') is None
        and квитанция['до'] == основание['поручение']['исходный_коммит']
        and квитанция['источник'] == основание['срез'], 'Нужна подтверждённая квитанция своего слияния')
    хранение.требовать(наблюдение['коммит'] == квитанция['до']
        and set(гит.служебные_состояния(корень)) == {'MERGE_HEAD'}
        and гит.гит(корень, 'rev-parse', 'MERGE_HEAD') == квитанция['источник']
        and гит.гит(корень, 'rev-parse', 'ORIG_HEAD') == квитанция['до'], 'Сдвинулось назначенное слияние')
    гит.поддержанное_дерево(корень, основание['срез'])
    дерево = гит.гит(корень, 'write-tree')
    if установлено:
        база = доставка_отчёта.дерево(корень, основание['дерево'])
        индекс = доставка_отчёта.дерево(корень, дерево)
        хранение.требовать(all(индекс.get(п) == з for п, з in база.items())
            and set(индекс) - set(база) <= допустимые
            and all(индекс[п]['режим'] == '100644' for п in set(индекс) - set(база)),
            'Индекс меняет срез либо выходит за конечные пути Журнала')
    else:
        хранение.требовать(дерево == основание['дерево'], 'Индекс изменён до установки пары')
    изменения = {п.decode() for п in гит.выполнить(корень, 'diff', '--no-ext-diff', '--no-textconv',
        '--ignore-submodules=none', '--name-only', '-z').stdout.split(b'\0') if п}
    хранение.требовать(изменения <= допустимые, 'Рабочие изменения вне новой пары')
    защищённые = гит.защищённые_файлы(корень)
    хранение.требовать({п: з for п, з in защищённые.items() if п not in допустимые}
        == квитанция['защищённые'], 'Изменены защищённые файлы вне новой пары')

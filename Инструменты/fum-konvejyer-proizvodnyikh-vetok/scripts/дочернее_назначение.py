"""Собственный читатель назначения; живой checkout координатора не нужен."""
import hashlib
import os
from pathlib import Path

import план_запуска_слоёв
import приём_направления as хранение
import постановка_задачи as постановка
import исполнитель_приёма as приём
from отложенные_назначения import манифест_коммита
import нативное_назначение
import поручение_слоя
import область_писателя
import снимок_области

КОД = {Path(м.__file__).resolve(): hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
       for м in (план_запуска_слоёв, нативное_назначение, поручение_слоя, постановка, хранение, приём)}
КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def проверить_код(корень, база):
    приём.проверить_инструменты(корень, база)
    область_писателя.проверить_код()
    for путь, ожидаемый in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == ожидаемый, "Код дочернего назначения изменён после загрузки")


def прочитать(корень, задача, источник):
    хранение.требовать(хранение.идентификатор_задачи(задача) and os.environ.get("CODEX_THREAD_ID") == задача,
                       "Нативный UUID не совпадает с дочерним писателем")
    корень = хранение.Хранилище(корень, задача).корень
    поручение = нативное_назначение.прочитать(источник)
    блок = поручение["назначение"]
    база, корневая = блок["база"], блок["корневая_задача"]
    хранение.требовать(хранение.шестнадцатеричный(база, 40), "Нужен полный OID коммита назначения")
    хранение.требовать(корневая != задача, "UUID дочернего писателя совпал с корневой задачей")
    проверить_код(корень, база)
    раннее = постановка.прочитать_подтверждение(корень, задача, база, источник)
    хранение.требовать(раннее["схема"] == "fum.начальная-база-задачи.2", "Нет раннего подтверждения полного поручения")
    файлы = манифест_коммита(корень, база, блок["файлы"])
    for ключ in ("план", "назначение"):
        хранение.путь_результата(блок[ключ])
        хранение.требовать(блок[ключ] in файлы, "Сокращён манифест первоначального назначения")
    описание = план_запуска_слоёв.проверить_план(хранение.разобрать(файлы[блок["план"]]))
    хранение.требовать(all(э["поручение"] in файлы for э in описание["слои"]), "Сокращён манифест поручений слоёв")
    слои = {э["слой"]: э for э in описание["слои"]}
    хранение.требовать(хранение.текст(блок["слой"]) and блок["слой"] in слои, "Неизвестный слой назначения")
    слой = слои[блок["слой"]]
    хранение.требовать(слой["ветка"] == раннее["ref"], "Назначение другого ref слоя")
    ожидаемый = поручение_слоя.сформировать(файлы[слой["поручение"]].decode("utf-8"), слой, база, блок)
    хранение.требовать(ожидаемый == поручение["текст"], "Полное первоначальное поручение не совпало с C")
    каталоги = область_писателя.каталоги_назначения(корень, база, корневая, блок["план"], описание,
                                                 хранение.разобрать(файлы[блок["назначение"]]))[блок["слой"]]
    снимок = снимок_области.снимок(корень, задача, база, каталоги)
    результат = {"схема": "fum.дочернее-назначение-слоя.1", "корневая_задача": корневая, "база": база,
                 "слой": блок["слой"], "писатель": снимок["владелец"], "каталоги": каталоги,
                 "назначение": блок, "источник": поручение["источник"], "раннее_sha256": хранение.хэш(раннее),
                 "снимок": снимок, "разрешение_записи": False}
    хранение.требовать(нативное_назначение.прочитать(источник) == поручение
                       and постановка.прочитать_подтверждение(корень, задача, база, источник) == раннее
                       and снимок_области.снимок(корень, задача, база, каталоги) == снимок,
                       "Состояние сдвинулось при чтении дочернего назначения")
    проверить_код(корень, база)
    return {**результат, "sha256": хранение.хэш(результат)}

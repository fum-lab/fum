"""Наблюдение остановленного до назначения ветки ребёнка; без его мутации."""
import hashlib
import os
from pathlib import Path

import приём_направления as хранение
import постановка_задачи as постановка


def снимок(вход):
    хранение.поля(вход, {"путь", "граница", "sha256"})
    хранение.требовать(type(вход["путь"]) is str and Path(вход["путь"]).is_absolute()
                       and type(вход["граница"]) is int and 0 < вход["граница"] <= 16 * 1024 * 1024
                       and хранение.шестнадцатеричный(вход["sha256"]), "Нужен ограниченный живой источник ребёнка")
    путь = Path(вход["путь"])
    хранение.безопасный_путь(путь)
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
        до = os.fstat(поток.fileno())
        хранение.требовать(до.st_size == вход["граница"], "Живой источник ребёнка изменился")
        данные = поток.read(вход["граница"] + 1)
        после = путь.stat()
        хранение.требовать((до.st_dev, до.st_ino, до.st_size, до.st_mtime_ns)
                           == (после.st_dev, после.st_ino, после.st_size, после.st_mtime_ns), "Источник ребёнка сдвинулся при чтении")
    хранение.требовать(len(данные) == вход["граница"] and данные.endswith(b"\n")
                       and hashlib.sha256(данные).hexdigest() == вход["sha256"], "Подменён источник ребёнка")
    записи = [хранение.разобрать(строка) for строка in данные.splitlines()]
    хранение.требовать(all(type(з) is dict for з in записи), "Неизвестная запись ребёнка")
    return записи


def подтвердить_ход(записи, задача, ожидание, разрешить_выгруженность=False, *, корень=None):
    """Только завершённый native ход; Git и полномочия проверяет вызывающий слой."""
    хранение.требовать(type(разрешить_выгруженность) is bool, "Неизвестный режим остановки")
    хранение.требовать(type(записи) is list and записи, "Нет записей ребёнка")
    позиция = len(записи) - 1
    while разрешить_выгруженность and позиция >= 0:
        запись = записи[позиция]
        данные = запись.get('payload') if type(запись) is dict else None
        if запись.get('type') != 'event_msg' or type(данные) is not dict or данные.get('type') != 'thread_settings_applied':
            break
        хранение.требовать(set(данные) == {'type', 'thread_id', 'thread_settings'}
            and данные['thread_id'] == задача and type(данные['thread_settings']) is dict
            and type(корень) is str and Path(корень).is_absolute()
            and данные['thread_settings'].get('cwd') == корень,
            'Чужие или неполные настройки после остановки')
        позиция -= 1
    хранение.требовать(позиция >= 0, 'Нет конечной остановки ребёнка')
    конец = записи[позиция]
    хранение.требовать(конец.get("type") == "event_msg" and type(конец.get("payload")) is dict
                       and конец["payload"].get("type") == "task_complete", "Нет конечной остановки ребёнка")
    ход = конец["payload"].get("turn_id")
    хранение.требовать(хранение.идентификатор_задачи(ход), "Нет UUID завершённого хода")
    содержимое = ожидание["ответ"]["content"]
    хранение.требовать(len(содержимое) == 1 and содержимое[0].get("type") == "text", "Нет полного ответа ожидания")
    ответ = хранение.разобрать(содержимое[0]["text"].encode())
    опросы = ответ.get("polls") if type(ответ) is dict else None
    хранение.требовать(type(опросы) is list, "Нет наблюдения состояния задачи")
    свои = [п for п in опросы if type(п) is dict and type(п.get("thread")) is dict and п["thread"].get("id") == задача]
    хранение.требовать(len(свои) == 1, "Нет единственного наблюдения ребёнка")
    опрос = свои[0]
    статусы = [{"type": "idle"}] + ([{"type": "notLoaded"}] if разрешить_выгруженность else [])
    хранение.требовать(опрос["thread"].get("status") in статусы
                       and type(опрос.get("latestTurn")) is dict and опрос["latestTurn"].get("id") == ход
                       and опрос["latestTurn"].get("status") == "completed" and опрос["latestTurn"].get("error") is None,
                       "Последнее ожидание не подтверждает конечный ход ребёнка")
    return ход


def проверить(исполнитель, слой, база, prompt, ожидание):
    корень = Path(слой["корень"])
    хранение.требовать(корень.is_absolute() and str(корень.resolve()) == str(корень)
                       and корень != исполнитель.корень, "Нужен отдельный физический корень ребёнка")
    хранение.безопасный_путь(корень, каталог=True)
    задача = слой["задача"]
    хранение.требовать(хранение.идентификатор_задачи(задача) and задача != исполнитель.задача, "Нужен отдельный UUID ребёнка")
    записи = снимок(слой["источник"])
    начало, контекст, граница = постановка.прочитать_начало_источника(слой["источник"]["путь"])
    хранение.требовать(начало.get("id") == задача and начало.get("cwd") == str(корень)
                       and контекст.get("cwd") == str(корень) and начало.get("git", {}).get("commit_hash") == база,
                       "Чужая нативная задача, дерево или C ребёнка")
    хранение.требовать(контекст.get("model") == "gpt-6-astra" and контекст.get("effort") == "low", "Первая модель ребёнка не совпала")
    поручение = постановка.проверить_нативное_поручение(слой["источник"]["путь"], исполнитель.задача, prompt, кодирование="xml-v1")
    ход = подтвердить_ход(записи, задача, ожидание)
    проверить_дерево(исполнитель, слой, база)
    return {"задача": задача, "корень": str(корень), "C": база, "ход": ход,
            "источник": слой["источник"], "начало": граница, "поручение": поручение,
            "ожидание": ожидание["источник"], "граница_гарантии": "наблюдение Git и кооперативная остановка"}


def проверить_дерево(исполнитель, слой, база):
    корень = Path(слой["корень"])
    хранение.безопасный_путь(корень, каталог=True)
    гит = lambda *а: хранение.гит(корень, "-c", "core.fsmonitor=false", "-c", "core.fileMode=true", *а)
    хранение.требовать(Path(гит("rev-parse", "--show-toplevel").strip()).resolve() == корень
                       and Path(гит("rev-parse", "--path-format=absolute", "--git-common-dir").strip()) == исполнитель.хранилище.общий,
                       "Дерево ребёнка относится к другой Git-базе")
    хранение.требовать(гит("rev-parse", "--symbolic-full-name", "HEAD").strip() == "HEAD"
                       and гит("rev-parse", "HEAD").strip() == база, "Ребёнок уже сменил detached C")
    флаги = гит("ls-files", "-v", "-z")
    хранение.требовать(all(ф[:1] == "H" for ф in флаги.split("\0") if ф), "Скрывающий изменения флаг индекса")
    хранение.требовать(not гит("status", "--porcelain=v1", "--untracked-files=all", "--ignore-submodules=none").strip(), "Дерево ребёнка содержит правки")
    гит("diff", "--exit-code", "--no-ext-diff", "--no-textconv", "--ignore-submodules=none", база, "--")
    гит("diff", "--cached", "--exit-code", "--no-ext-diff", "--no-textconv", база, "--")
    раннее = постановка.путь_подтверждения(корень)
    хранение.безопасный_путь(раннее)
    хранение.требовать(not раннее.exists(), "У ребёнка уже есть раннее подтверждение записи")

ПРЕДЕЛ = 16 * 1024 * 1024


def прочитать_вход(источник, остановка, корневая, задача, корень, текст):
    путь = Path(источник)
    хранение.требовать(путь.is_absolute(), 'Нужен абсолютный нативный источник получателя')
    хранение.безопасный_путь(путь)
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        хранение.требовать(stat.S_ISREG(до.st_mode) and 0 < до.st_size <= ПРЕДЕЛ,
                           'Нужен ограниченный обычный источник получателя')
        сырые = поток.read(ПРЕДЕЛ + 1)
        после = путь.stat()
        хранение.требовать((до.st_dev, до.st_ino, до.st_size, до.st_mtime_ns)
            == (после.st_dev, после.st_ino, после.st_size, после.st_mtime_ns),
            'Нативный источник получателя изменился при чтении')
    хранение.требовать(len(сырые) == до.st_size, 'Оборван нативный источник получателя')
    return прочитать_байты_входа(сырые, остановка, корневая, задача, корень, текст)


def прочитать_байты_входа(сырые, остановка, корневая, задача, корень, текст):
    """Тот же транспортный контракт над уже проверенными полными байтами."""
    return _прочитать_байты_входа(сырые, остановка, корневая, задача, корень, текст, False)[0]


def прочитать_рамки_входа(сырые, остановка, корневая, задача, корень, текст):
    """Вернуть также самостоятельно разобранные рамки для следующего чистого слоя."""
    return _прочитать_байты_входа(сырые, остановка, корневая, задача, корень, текст, True)


def _прочитать_байты_входа(сырые, остановка, корневая, задача, корень, текст, с_рамками):
    хранение.требовать(type(сырые) is bytes and 0 < len(сырые) <= ПРЕДЕЛ and сырые.endswith(b'\n'),
        'Оборван или неограничен нативный источник получателя')
    хранение.поля(остановка, {'путь', 'граница', 'sha256'})
    граница = остановка['граница']
    хранение.требовать(type(граница) is int and 0 < граница < len(сырые)
        and хранение.шестнадцатеричный(остановка['sha256']) and сырые[граница - 1:граница] == b'\n'
        and hashlib.sha256(сырые[:граница]).hexdigest() == остановка['sha256'],
        'Нативный вход не продолжает подтверждённую остановку')
    начало = хранение.разобрать(сырые.split(b'\n', 1)[0])
    хранение.требовать(начало.get('type') == 'session_meta' and type(начало.get('payload')) is dict
        and начало['payload'].get('id') == задача and начало['payload'].get('cwd') == корень,
        'Источник принадлежит другому получателю')
    найдено = None; рамки = []
    позиция = 0
    контроль = контроль_первичного_потока.КонтрольПервичногоПотока()
    первоначальных = 0
    for строка in сырые.splitlines(keepends=True):
        запись = хранение.разобрать(строка)
        хранение.требовать(type(запись) is dict, 'Неизвестная нативная запись получателя')
        данные = запись.get('payload', {})
        хранение.требовать(type(данные) is dict, 'Неизвестный payload получателя')
        контроль.проверить(запись)
        if позиция < граница and запись.get('type') == 'response_item' \
                and данные.get('type') == 'function_call_output' and данные.get('name') in {'create_thread', 'send_message_to_thread', 'handoff_thread'}:
            первоначальных += 1
            хранение.требовать(первоначальных == 1 and данные['name'] == 'create_thread',
                'Другое либо повторное поручение в остановленном префиксе получателя')
        if позиция >= граница and запись.get('type') == 'response_item' and данные.get('type') == 'function_call_output' \
                and данные.get('name') in {'create_thread', 'send_message_to_thread', 'handoff_thread'}:
            хранение.требовать(найдено is None and данные['name'] == 'send_message_to_thread'
                and type(данные.get('output')) is str, 'Другой либо повторный нативный вход получателя')
            транспорт = re.fullmatch(r'<codex_delegation>\n  <source_thread_id>([^<\n]+)</source_thread_id>\n  <input>(.*)</input>\n</codex_delegation>',
                                      данные['output'], re.S)
            хранение.требовать(транспорт is not None and транспорт[1] == корневая,
                               'Неизвестный либо чужой отправитель нативного входа')
            декодировано = html.unescape(транспорт[2])
            хранение.требовать(html.escape(декодировано, quote=False) == транспорт[2] and декодировано == текст,
                               'Нативный вход не совпал с адресным поручением')
            конец = позиция + len(строка)
            найдено = {'начало': позиция, 'конец': конец, 'sha256': hashlib.sha256(строка).hexdigest(),
                       'префикс_sha256': hashlib.sha256(сырые[:конец]).hexdigest()}
        if с_рамками:рамки.append((позиция, позиция+len(строка), запись))
        позиция += len(строка)
    хранение.требовать(найдено is not None, 'Адресное поручение ещё не получено нативным транспортом')
    return найдено, рамки


def прочитать_отправку(свидетельство, корневая, задача, корень, текст):
    """Подтвердить завершённый send, ещё не требуя получения ребёнком."""
    хранение.поля(свидетельство, {'схема', 'координатор', 'остановка', 'ожидание', 'возобновление'})
    хранение.требовать(свидетельство['схема'] == 'fum.свидетельство-дочернего-приёма.1'
        and хранение.идентификатор_задачи(корневая) and хранение.идентификатор_задачи(задача)
        and корневая != задача and isinstance(текст, str) and bool(текст.strip()) and '\0' not in текст,
        'Неизвестное свидетельство дочернего приёма')
    нативный = нативные_вызовы.прочитать(свидетельство['координатор'], корневая,
        ожидания=[задача], интервалы=True, читать_создания=False)
    хранение.требовать(нативный['источник']['начало'] == нативный['начальная_граница'],
                       'Нужна полная история адресных воздействий')
    ожидания, воздействия = нативный['ожидания'], нативный['возобновления']
    хранение.требовать(ожидания and ожидания[-1]['id'] == свидетельство['ожидание']
        and len(воздействия) == 1 and воздействия[0]['id'] == свидетельство['возобновление'],
        'Нужны последнее ожидание и единственный адресный send')
    ожидание, send = ожидания[-1], воздействия[0]
    аргументы = send['аргументы']
    хранение.требовать(send['инструмент'] == 'send_message_to_thread'
        and set(аргументы) <= {'threadId', 'prompt', 'hostId', 'model', 'thinking'}
        and аргументы.get('threadId') == задача and аргументы.get('prompt') == текст,
        'Не совпали адрес либо текст завершённого send')
    хранение.требовать(ожидание['источник']['конец'] <= send['источник']['начало']
        and ожидание['интервал']['конец_мс'] < send['интервал']['начало_мс'],
        'Send начался до подтверждения остановки или перекрыл ожидание')
    записи = остановка_ребёнка.снимок(свидетельство['остановка'])
    ход = остановка_ребёнка.подтвердить_ход(записи, задача, ожидание, True, корень=корень)
    return {'схема': 'fum.нативный-приём.1', 'корневая_задача': корневая, 'исполнитель': задача,
        'текст': текст, 'остановленный_ход': ход, 'ожидание': ожидание['источник'],
        'отправка': send['источник'],
        'свидетельство_sha256': хранение.хэш(свидетельство),
        'граница': 'Наблюдённый нативный транспорт; разрешение записи проверяется отдельно'}


def прочитать(свидетельство, корневая, задача, корень, источник, текст):
    отправка = прочитать_отправку(свидетельство, корневая, задача, корень, текст)
    получено = прочитать_вход(источник, свидетельство['остановка'], корневая, задача, корень, текст)
    return {**отправка, 'получение': получено}

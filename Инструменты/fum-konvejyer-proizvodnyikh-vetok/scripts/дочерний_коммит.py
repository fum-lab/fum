"""Закрытый допуск конечной передачи слоя; не приёмка общей интеграции."""
from pathlib import Path, PurePosixPath

import дочернее_назначение
import запись_слоя
import нативное_назначение
import приём_направления as хранение
import снимок_области


def проверить(параметры):
    назначение = дочернее_назначение.прочитать(параметры['корень'], параметры['исполнитель'], параметры['источник_модели'])
    хранение.требовать(параметры['задача'] == назначение['корневая_задача']
        and параметры['ветка'] == назначение['писатель']['ref']
        and параметры['корень'] == назначение['писатель']['путь'], 'Не совпали роли и адрес дочернего назначения')
    хранение.требовать(хранение.хэш(дочернее_назначение.привязка(назначение)) == параметры['назначение_sha256'],
                       'Изменена привязка дочернего назначения')
    хранение.требовать(параметры['источники'] == [], 'Передача принимает только первоначальное поручение корня')
    журнал = назначение['каталоги'][1]
    хранение.требовать(параметры['запрос'] == журнал + 'запрос.md'
        and параметры['история_модели'].startswith(журнал + 'материалы/'), 'Подменён собственный Журнал назначения')
    цели = параметры['разрешённые_цели']
    хранение.требовать(isinstance(цели, list) and bool(цели) and len(set(цели)) == len(цели), 'Нужен конечный состав целей')
    хранение.требовать({журнал + 'запрос.md', журнал + 'отчёт.md', параметры['история_модели']} <= set(цели),
                       'Будущие записи пары и истории отсутствуют в составе')
    корень = Path(параметры['корень'])
    for имя in цели:
        хранение.требовать(isinstance(имя, str) and any(имя.startswith(п) for п in назначение['каталоги']),
                           'Будущая цель вне области писателя: ' + str(имя))
        хранение.требовать(not any(ord(знак) < 32 for знак in имя), 'Управляющий символ в пути')
        путь = снимок_области.охват.точный_путь(корень, имя)
        хранение.требовать(снимок_области.охват.состояние_пути(путь)['тип'] in {'файл', 'отсутствует'},
                           'Будущая цель не является обычным файлом')
        for предок in путь.parents:
            if предок == корень:
                break
            хранение.требовать(not предок.exists() or предок.is_dir(), 'Родитель будущей цели не является каталогом')
    запись_слоя.проверить_коллизии([PurePosixPath(имя) for имя in цели])
    запись_слоя.проверить_игнорирование(корень, цели)
    приватные = [Path(параметры[к]) for к in ('источник_модели', 'кэш_модели', 'сообщение', 'подготовка', 'квитанция')]
    хранение.требовать(len(set(приватные)) == len(приватные), 'Приватные пути совпали между собой или с исходником')
    for путь in приватные:
        хранение.требовать(путь.is_absolute() and путь == путь.resolve()
            and not any((п / '.git').exists() for п in путь.parents), 'Приватный путь дочерней передачи находится в Git')
    return назначение


def первичные(параметры):
    назначение = проверить(параметры)
    поручение = нативное_назначение.прочитать(параметры['источник_модели'])
    # Новые человеческие уточнения нельзя незаметно потерять при передаче
    # конечного первоначального поручения. Их разбирает координатор.
    from сообщения_задачи import прочитать_сообщения
    сообщения = прочитать_сообщения(параметры['источник_модели'], параметры['исполнитель'],
        корень_репозитория=параметры['корень'], без_записи=True)
    хранение.требовать(сообщения['полнота_подтверждена'] and not сообщения['дописано_после_снимка']
        and not any(э['происхождение'] == 'человек' for э in сообщения['сообщения']),
        'Первоначальная передача требует разбора поздних уточнений координатором')
    return [{'задача': назначение['корневая_задача'], 'исполнитель': параметры['исполнитель'],
             'экземпляр': хранение.хэш(поручение), 'происхождение': 'поручение-корня',
             'позиция': поручение['источник'], 'текст': поручение['текст']}]


def связность(параметры, сообщение, валидатор):
    from связность_слоя import проверить
    return проверить(параметры, сообщение, валидатор)

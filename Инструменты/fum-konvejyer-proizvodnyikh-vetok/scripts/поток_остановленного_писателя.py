"""Полный первичный поток одного остановленного писателя, без смены его UUID."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import приём_направления as хранение
import снимок_нативного_источника as снимок
import контроль_первичного_потока
import остановка_ребёнка


def прочитать(описание, задача, корень, база, модель, усилие, ожидание):
    хранение.поля(описание, {'путь', 'граница', 'sha256'})
    сырые, идентичность = снимок._сырой(описание['путь'])
    хранение.требовать(type(описание['граница']) is int and len(сырые) == описание['граница']
        and hashlib.sha256(сырые).hexdigest() == описание['sha256'], 'Изменён полный источник писателя')
    контроль = контроль_первичного_потока.КонтрольПервичногоПотока()
    записи, контексты, создания, начала, концы = [], [], [], [], []
    мир = False
    for raw in сырые.splitlines(keepends=True):
        запись = хранение.разобрать(raw)
        хранение.требовать(type(запись) is dict and type(запись.get('payload')) is dict,
            'Неизвестная запись полного потока писателя')
        данные = запись['payload']; тип, вид = запись.get('type'), данные.get('type')
        копия = контроль.проверить(запись)
        if концы:
            хранение.требовать(тип == 'event_msg' and вид == 'thread_settings_applied',
                'После конечной остановки появились новые события')
        if тип == 'session_meta':
            хранение.требовать(not записи and данные.get('id') == задача and данные.get('cwd') == корень
                and данные.get('git', {}).get('commit_hash') == база, 'Чужая начальная идентичность писателя')
        elif тип == 'world_state':
            хранение.требовать(not мир and not создания and not контексты, 'Повтор или поздний начальный world_state')
            мир = True
        elif тип == 'turn_context':
            хранение.требовать(данные.get('cwd') == корень
                and (данные.get('model'), данные.get('effort')) == (модель, усилие),
                'Сменились cwd, модель или усилие полного потока писателя')
            контексты.append(данные)
        elif тип == 'event_msg' and вид == 'task_started':
            хранение.требовать(not начала and not создания, 'Повторное начало работы писателя')
            начала.append(данные)
        elif тип == 'event_msg' and вид == 'task_complete':
            концы.append(данные)
        elif тип == 'event_msg' and вид == 'thread_settings_applied':
            хранение.требовать(bool(концы), 'Настройки посреди первичной работы требуют разбора')
        elif тип == 'response_item' and вид == 'message' and данные.get('role') == 'user':
            pass  # Точный единственный начальный контекст уже проверен общим контролем.
        elif тип == 'response_item' and вид == 'function_call_output' and данные.get('name') in снимок.ТРАНСПОРТЫ:
            хранение.требовать(данные['name'] == 'create_thread' and not создания,
                'Новое поручение остановленного писателя')
            создания.append(данные)
        elif not копия:
            снимок.проверить_запись(запись)
        записи.append(запись)
    хранение.требовать(записи and записи[0]['type'] == 'session_meta'
        and контексты and len(создания) == len(концы) == 1, 'Неполный первичный поток писателя')
    ход = остановка_ребёнка.подтвердить_ход(записи, задача, ожидание, True, корень=корень)
    хранение.требовать(not начала or начала[0].get('turn_id') == ход, 'Начало и остановка принадлежат разным ходам')
    return сырые, идентичность, ход

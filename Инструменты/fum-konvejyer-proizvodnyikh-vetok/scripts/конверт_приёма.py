"""Опубликовать вход после send; ожидание получателя только читает."""
import os
from pathlib import Path
import sys
import time

import приём_интеграции
import нативный_приём
import снимок_нативного_источника as снимок
import создание_коммита

хранение = снимок.хранение
файлы = снимок.файлы
КОРЕНЬ_СОСТОЯНИЯ = (Path('/Users/Shared') / ('FUM-private-' + str(os.getuid()))
    if sys.platform == 'darwin' else Path.home() / '.local/state/FUM')
ПОЛЯ = {'схема', 'текст', 'план', 'владельцы', 'свидетельство', 'коммит', 'sha256'}


def разобрать_текст(текст):
    начало, конец = приём_интеграции.НАЧАЛО, приём_интеграции.КОНЕЦ
    хранение.требовать(type(текст) is str and текст.startswith(начало) and текст.endswith(конец),
        'Нужен канонический текст приёма')
    блок = хранение.разобрать(текст[len(начало):-len(конец)].encode('utf-8'))
    хранение.требовать(приём_интеграции.сформировать(блок) == текст, 'Изменён канонический текст приёма')
    хранение.требовать(блок['корневая_задача'] != блок['исполнитель'], 'Корень не является своим получателем')
    return блок


def адрес(текст, *, получатель=False):
    блок = разобрать_текст(текст)
    ключ = хранение.хэш({к: блок[к] for к in ('корневая_задача', 'исполнитель', 'план', 'назначение_sha256')})
    база = Path(КОРЕНЬ_СОСТОЯНИЯ)
    хранение.требовать(база.is_absolute() and база == база.resolve(), 'Нужен физический корень хранения')
    путь = база / блок['исполнитель' if получатель else 'корневая_задача'] / (
        'приёмы' if получатель else 'входы-приёма') / ключ
    хранение.безопасный_путь(путь, каталог=True)
    for предок in [путь, *путь.parents]:
        хранение.требовать(not os.path.lexists(предок / '.git')
            and not ((предок / 'objects').is_dir() and (предок / 'HEAD').exists()),
            'Приватный приём запрещён внутри Git')
        if предок == база or предок.is_relative_to(база):
            if предок.exists():
                файлы._приватный(предок, каталог=True)
    return путь


def проверить(пакет, текст):
    хранение.поля(пакет, ПОЛЯ)
    хранение.требовать(пакет['схема'] == 'fum.конверт-дочернего-приёма.1'
        and пакет['текст'] == текст and пакет['sha256'] == хранение.хэш(
            {к: з for к, з in пакет.items() if к != 'sha256'}), 'Изменён конверт приёма')
    блок = разобрать_текст(текст)
    план = приём_интеграции.доставка_план.проверить_план(пакет['план'])
    приём_интеграции.доставка_план.сверить_реестр(пакет['владельцы'], план.get('назначение'))
    хранение.требовать(план['идентификатор'] == блок['план']
        and план['владельцы_sha256'] == хранение.хэш(пакет['владельцы']), 'Подменены план или владельцы')
    источник = план['источник']
    хранение.требовать(источник['владелец'] == блок['корневая_задача']
        and источник['срез'] == блок['срез'] and источник['коммит'] == блок['источник_приёмки'],
        'Конверт другого корня либо принятого среза')
    свои = [п for п in план['получатели'] if п['владелец'] == блок['исполнитель']
        or п['корень'] == блок['корень'] or п['ref'] == блок['ref']]
    хранение.требовать(len(свои) == 1 and all(свои[0][к] == блок[з] for к, з in (
        ('владелец', 'исполнитель'), ('корень', 'корень'), ('ref', 'ref'), ('коммит', 'исходный_коммит'))),
        'Конверт другого получателя')
    for п in план['получатели']:
        запись = пакет['владельцы'].get(п['корень'])
        хранение.требовать(type(запись) is dict and запись.get('задача') == п['владелец']
            and запись.get('ref') == п['ref'], 'Получатель не связан с реестром')
    хранение.поля(пакет['коммит'], {'имя_автора', 'заголовок', 'описание'})
    хранение.требовать(all(хранение.текст(з) and '\0' not in з for з in пакет['коммит'].values())
        and создание_коммита.проверить_роль(пакет['коммит']['имя_автора']), 'Неверные поля коммита приёма')
    хранение.поля(пакет['свидетельство'], {'схема', 'координатор', 'остановка', 'ожидание', 'возобновление'})
    return блок


def прочитать(текст):
    путь = адрес(текст)
    готовность = путь / 'готово.json'
    хранение.безопасный_путь(готовность)
    if not готовность.exists():
        return None
    хранение.требовать({п.name for п in путь.iterdir()} == {'конверт.json', 'готово.json'},
        'Неполная либо лишняя часть готового конверта')
    сырые = файлы._читать(путь / 'конверт.json')
    пакет = хранение.разобрать(сырые)
    хранение.требовать(хранение.байты(пакет) == сырые, 'Неканонический конверт')
    проверить(пакет, текст)
    маркер = хранение.разобрать(файлы._читать(готовность))
    хранение.требовать(маркер == {'схема': 'fum.готовый-конверт-приёма.1', 'sha256': хранение.хэш(пакет)},
        'Подменена готовность конверта')
    return пакет


def установить_готовность(путь, пакет):
    временный = путь / '.готово.tmp'
    файлы._записать(временный, хранение.байты({
        'схема': 'fum.готовый-конверт-приёма.1', 'sha256': хранение.хэш(пакет)}))
    хранение.требовать(not os.path.lexists(путь / 'готово.json'), 'Готовность уже установлена')
    # Единственный кооперативный писатель удерживает замок; читатель видит целый файл.
    os.rename(временный, путь / 'готово.json')
    хранение.синхронизировать_каталог(путь)
    хранение.синхронизировать_каталог(путь.parent)


def опубликовать(текст, план, владельцы, свидетельство, коммит):
    данные = {'схема': 'fum.конверт-дочернего-приёма.1', 'текст': текст,
        'план': план, 'владельцы': владельцы, 'свидетельство': свидетельство, 'коммит': коммит}
    пакет = {**данные, 'sha256': хранение.хэш(данные)}
    блок = проверить(пакет, текст)
    хранение.требовать(os.environ.get('CODEX_THREAD_ID') == блок['корневая_задача'],
        'Публикация принадлежит нативной корневой задаче')
    нативный_приём.прочитать_отправку(свидетельство, блок['корневая_задача'],
        блок['исполнитель'], блок['корень'], текст)
    путь = адрес(текст)
    хранение.создать_каталоги(путь.parent, Path(путь.anchor), права=0o700)
    адрес(текст)
    with снимок.сообщения_задачи._замок(путь.with_suffix('.публикация.json')):
        if путь.exists():
            прежний = прочитать(текст)
            хранение.требовать(прежний is not None, 'Неполная публикация требует разбора координатором')
            хранение.требовать(прежний == пакет, 'Изменён уже опубликованный конверт')
            хранение.синхронизировать_каталог(путь)
            хранение.синхронизировать_каталог(путь.parent)
            хранение.требовать(прочитать(текст) == пакет, 'Конверт изменился при синхронизации')
            return прежний
        путь.mkdir(mode=0o700)
        файлы._записать(путь / 'конверт.json', хранение.байты(пакет))
        установить_готовность(путь, пакет)
        хранение.требовать(прочитать(текст) == пакет, 'Изменился опубликованный конверт')
    return пакет


def ожидать(текст, предел_секунд=30):
    блок = разобрать_текст(текст)
    хранение.требовать(os.environ.get('CODEX_THREAD_ID') == блок['исполнитель'], 'Ожидание другого получателя')
    хранение.требовать(type(предел_секунд) in (int, float) and 0 <= предел_секунд <= 60,
        'Один читающий вызов ожидает не более 60 секунд')
    конец = time.monotonic() + предел_секунд
    while True:
        пакет = прочитать(текст)
        if пакет is not None:
            return пакет
        остаток = конец - time.monotonic()
        if остаток <= 0:
            return None
        time.sleep(min(0.2, остаток))

"""Прочитать точный завершённый CLI-отказ, не приписывая ему исход старого Git."""
import hashlib
import io
import re
import shlex
from pathlib import PurePosixPath
from urllib.parse import unquote, urlsplit

import приём_направления as хранение

ПРЕДЕЛ = 16 * 1024 * 1024
КОМАНДА = ('python3', '-B',
    'Инструменты/fum-konvejyer-proizvodnyikh-vetok/scripts/подготовить-приём.py',
    'принять', '--исходник')


def вызов(сырые, цель):
    хранение.поля(цель, {'задача', 'ход', 'корень', 'исходник', 'id', 'начало', 'конец', 'sha256'})
    хранение.требовать(type(сырые) is bytes and 0 < len(сырые) <= ПРЕДЕЛ
        and сырые.endswith(b'\n'), 'Нужен ограниченный полный JSONL с конечным LF')
    хранение.требовать(хранение.идентификатор_задачи(цель['задача'])
        and хранение.идентификатор_задачи(цель['ход'])
        and all(хранение.текст(цель[к]) for к in ('корень', 'исходник', 'id'))
        and all(type(цель[к]) is int for к in ('начало', 'конец'))
        and 0 < цель['начало'] < цель['конец'] <= len(сырые)
        and хранение.шестнадцатеричный(цель['sha256']), 'Повреждён локатор первичного отказа')
    исходник = цель['исходник']
    путь = PurePosixPath(исходник)
    хранение.требовать(исходник.startswith('/') and not исходник.startswith('//')
        and исходник != '/' and путь.as_posix() == исходник and '..' not in путь.parts
        and '\x00' not in исходник, 'Нужен канонический абсолютный POSIX-путь исходника')
    позиция = 0
    найденные = []
    for строка in io.BytesIO(сырые):
        начало, позиция = позиция, позиция + len(строка)
        запись = хранение.разобрать(строка)
        хранение.требовать(type(запись) is dict and type(запись.get('payload')) is dict,
            'Неизвестная рамка первичного источника')
        данные = запись['payload']
        if начало == 0:
            хранение.требовать(запись.get('type') == 'session_meta'
                and данные.get('id') == цель['задача'] and данные.get('cwd') == цель['корень'],
                'Источник принадлежит другой задаче или каталогу')
        элемент = данные.get('item')
        if запись.get('type') != 'event_msg' or данные.get('type') != 'item_completed' \
                or type(элемент) is not dict or элемент.get('id') != цель['id']:
            continue
        хранение.требовать(элемент.get('type') == 'CommandExecution', 'Нужен первичный CommandExecution')
        найденные.append((начало, позиция, строка, данные, элемент))
    хранение.требовать(len(найденные) == 1, 'Нужен единственный завершённый первичный вызов')
    начало, конец, строка, данные, элемент = найденные[0]
    хранение.требовать((начало, конец, hashlib.sha256(строка).hexdigest())
        == (цель['начало'], цель['конец'], цель['sha256']), 'Подменена строка первичного отказа')
    хранение.требовать(данные.get('thread_id') == цель['задача']
        and данные.get('turn_id') == цель['ход'], 'Отказ относится к другому ходу или задаче')
    каталог = urlsplit(элемент.get('cwd', ''))
    хранение.требовать(каталог.scheme == 'file' and not каталог.netloc
        and not каталог.query and not каталог.fragment and unquote(каталог.path) == цель['корень'],
        'Вызов выполнен в другом каталоге')
    хранение.требовать(элемент.get('status') == 'failed'
        and type(элемент.get('exit_code')) is int and элемент['exit_code'] == 2,
        'Нет подтверждённого завершённого отказа CLI с кодом 2')
    хранение.требовать(элемент.get('source') == 'unified_exec_startup'
        and type(элемент.get('stdout')) is str and элемент['stdout'].endswith('\n')
        and элемент.get('stderr') == '',
        'Нужны первичные каналы известного отказа')
    старт, завершение = данные.get('started_at_ms'), данные.get('completed_at_ms')
    хранение.требовать(type(старт) is int and type(завершение) is int
        and 0 <= старт <= завершение, 'Нет завершённого интервала первичного вызова')
    return данные, элемент


def ответ(сырые):
    ответ = хранение.разобрать(сырые)
    хранение.поля(ответ, {'схема', 'ошибка', 'повтор_эффекта_разрешён', 'длительность_наносекунды'})
    хранение.требовать(ответ['схема'] == 'fum.отказ-обнаружения-приёма.1'
        and ответ['ошибка'] == 'Нужна подтверждённая квитанция своего слияния'
        and ответ['повтор_эффекта_разрешён'] is False
        and type(ответ['длительность_наносекунды']) is int
        and ответ['длительность_наносекунды'] >= 0, 'Это другой отказ или разрешение повторного эффекта')
    return ответ


def результат(цель, данные, stdout, ответ):
    return {'схема': 'fum.первичный-отказ-нативного-приёма.1', 'задача': цель['задача'],
        'ход': цель['ход'], 'id': цель['id'],
        'источник': {к: цель[к] for к in ('начало', 'конец', 'sha256')},
        'интервал': {'начало_мс': данные['started_at_ms'], 'конец_мс': данные['completed_at_ms']}, 'код': 2,
        'stdout_sha256': hashlib.sha256(stdout.encode()).hexdigest(),
        'stderr_sha256': hashlib.sha256(b'').hexdigest(),
        'ответ': ответ, 'исход_прежнего_слияния': 'unknown', 'повтор_эффекта_разрешён': False}


def проверить(сырые, цель):
    данные, элемент = вызов(сырые, цель)
    команда = элемент.get('command')
    аргументы = [*КОМАНДА, цель['исходник']]
    хранение.требовать(all('\x00' not in а for а in аргументы), 'Недопустимый нулевой байт команды')
    def буквальное(а):
        return "'" + а.replace("'", "'\\''") + "'" if '=' in а else shlex.quote(а)
    def слово(а):
        return а if re.fullmatch(r"[^\s;&|<>`$\\'\"(){}*?!~#^=\[\]]+", а) else буквальное(а)
    допустимые = {' '.join(map(слово, аргументы)), ' '.join(map(буквальное, аргументы))}
    хранение.требовать(type(команда) is list and len(команда) == 3
        and команда[:2] == ['/bin/zsh', '-lc'] and type(команда[2]) is str
        and команда[2] in допустимые,
        'Это другой процесс, а не назначенный CLI приёма')
    return результат(цель, данные, элемент['stdout'], ответ(элемент['stdout'].encode()))

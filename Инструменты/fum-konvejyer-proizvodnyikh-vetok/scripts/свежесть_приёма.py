"""Обновить только два Markdown нового J по каноническому входу приёма .4."""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import stat
import time

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import эпизод_приёма as эпизод
import коммит_приёма
import создание_коммита as коммит
import свежесть_слоя

хранение = эпизод.хранение
свежесть = свежесть_слоя.свежесть
каркас = коммит_приёма.план.каркас
КОД = {**свежесть_слоя.КОД,
    Path(__file__).resolve(): КОД_ПРИ_ЗАГРУЗКЕ,
    Path(каркас.__file__).resolve(): каркас.КОД_ПРИ_ЗАГРУЗКЕ}


def состояние(путь):
    хранение.безопасный_путь(путь)
    метаданные = путь.stat()
    хранение.требовать(stat.S_ISREG(метаданные.st_mode), 'Нужен обычный Markdown нового J')
    return путь.read_bytes(), stat.S_IMODE(метаданные.st_mode)


def подготовить_пару(корень, имена):
    """Внутренний читающий план; список целей даёт только проверенное основание."""
    хранение.требовать(len(имена) == 2 and len(set(имена)) == 2, 'Нужна ровно пара Markdown')
    время = свежесть.format_msk(свежесть.parse_now())
    файлы, прежние = [], {}
    for имя in имена:
        путь = корень / имя
        прежние[имя] = состояние(путь)
        сырые, режим = прежние[имя]
        хранение.требовать(b'\r' not in сырые, 'Свежесть приёма требует UTF-8 с LF')
        текст = сырые.decode('utf-8')
        содержание, метка, _ = свежесть.split_recency_block(текст, путь=путь, корень=корень)
        if метка is not None:
            хранение.требовать(свежесть.DISPLAY_TIME_RE.fullmatch(метка.timestamp) is not None,
                'Неверный формат времени свежести: ' + имя)
            свежесть.parse_display_time(метка.timestamp)
        запись, ошибки, изменён = свежесть.process_markdown_file(путь, корень, set(имена), время, True, False)
        хранение.требовать(not set(ошибки) - {'missing recency metadata: ' + имя,
            'stale recency metadata: ' + имя}, '; '.join(ошибки))
        хранение.требовать(состояние(путь) == прежние[имя], 'Markdown изменён во время чтения')
        if изменён:
            новое = свежесть.attach_recency_block(свежесть.canonical_content(содержание), запись.timestamp, запись.digest)
            файлы.append(каркас.PreparedFile(PurePosixPath(имя), новое.encode('utf-8'), режим))
    return файлы, прежние


def обновить(файл):
    начало = time.monotonic_ns()
    параметры = эпизод.прочитать_файл(файл)
    основание = коммит_приёма.адрес(параметры)
    путь = эпизод.путь_эпизода(основание)
    хранение.требовать(файл == путь.with_suffix('.вход-коммита.json'), 'Нужен сохранённый канонический вход приёма')
    корень = коммит.адрес_дерева(параметры)
    хранение.требовать(корень == Path.cwd().resolve(), 'Нужен физический cwd получателя')
    квитанция = Path(параметры['квитанция'])
    # Тот же кооперативный замок, что у создателя R, затем замок эпизода.
    with эпизод.файлы._замок(квитанция), эпизод.файлы._замок(путь.with_suffix('.исполнение.json')):
        хранение.требовать(not os.path.lexists(квитанция), 'После квитанции R свежесть не изменяется')
        def проверить():
            хранение.требовать(эпизод.прочитать_файл(файл) == параметры, 'Сдвинулся вход свежести')
            хранение.требовать(коммит_приёма.проверить(параметры) == основание, 'Сдвинулось основание свежести')
            коммит_приёма.приём_интеграции.проверить_код(корень,
                основание['поручение']['база'], дополнительный_код=КОД)
        проверить()
        допуск = time.monotonic_ns()
        имена = коммит_приёма.план.будущие_пути(основание)[:2]
        файлы, прежние = подготовить_пару(корень, имена)
        план = time.monotonic_ns()
        проверить()
        хранение.требовать(all(состояние(корень / имя) == значение for имя, значение in прежние.items()),
            'Пара изменилась перед установкой свежести')
        # Обычная ошибка откатывается готовой транзакцией. После жёсткого обрыва
        # неизвестный временный файл закрывает следующий допуск всего J.
        каркас._apply_prepared_transaction(корень, файлы)
        проверить()
    return {'схема': 'fum.свежесть-дочернего-приёма.1', 'цели': имена,
        'изменены': [ф.path.as_posix() for ф in файлы], 'профиль': {
            'первый_допуск_наносекунды': допуск - начало, 'план_наносекунды': план - допуск,
            'повторный_допуск_и_установка_наносекунды': time.monotonic_ns() - план},
        'длительность_наносекунды': time.monotonic_ns() - начало}


def главная(аргументы=None):
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--вход', type=Path, required=True)
    вход = парсер.parse_args(аргументы)
    try:
        результат = обновить(вход.вход)
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as ошибка:
        print(json.dumps({'ошибка': str(ошибка), 'повтор_эффекта_разрешён': False}, ensure_ascii=False))
        return 2
    print(json.dumps(результат, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(главная())

"""Связь исторических sends корня с их точным получением остановленными детьми."""
import hashlib
import html

import приём_направления as хранение
import снимок_нативного_источника as снимок


def проверить(исполнитель, вход, нативный, попытки):
    перечень = вход['возобновления']
    хранение.требовать(type(перечень) is dict and len(перечень) <= 16, 'Нужен конечный перечень исторических отправок')
    отправки = нативный['возобновления']
    хранение.требовать(set(перечень) == {о['id'] for о in отправки}, 'Не совпал полный перечень возобновлений')
    по_детям = {имя: [] for имя in вход['слои']}
    for отправка in отправки:
        описание = перечень[отправка['id']]
        хранение.поля(описание, {'слой', 'аргументы_sha256', 'ответ_sha256'})
        имя = описание['слой']
        хранение.требовать(имя in вход['слои'], 'Возобновление относится к другому слою')
        аргументы = отправка['аргументы']
        профиль = попытки[имя]['аргументы']
        хранение.требовать(отправка['инструмент'] == 'send_message_to_thread'
            and set(аргументы) <= {'threadId', 'hostId', 'prompt', 'model', 'thinking'}
            and аргументы.get('threadId') == вход['слои'][имя]['задача']
            and хранение.текст(аргументы.get('prompt'))
            and аргументы.get('model', профиль['model']) == профиль['model']
            and аргументы.get('thinking', профиль['thinking']) == профиль['thinking']
            and описание['аргументы_sha256'] == хранение.хэш(аргументы)
            and описание['ответ_sha256'] == хранение.хэш(отправка['ответ']),
            'Подменены адрес, профиль, аргументы или ответ исторического send')
        по_детям[имя].append(отправка)
    результаты = {}
    for имя, слой in вход['слои'].items():
        сырые, _ = снимок._сырой(слой['источник']['путь'])
        хранение.требовать(len(сырые) == слой['источник']['граница']
            and hashlib.sha256(сырые).hexdigest() == слой['источник']['sha256'], 'Изменён живой источник возобновлённого ребёнка')
        полученные, начала, позиция = [], 0, 0
        исходный, дубль = None, False
        for строка in сырые.splitlines(keepends=True):
            запись = хранение.разобрать(строка); данные = запись.get('payload')
            хранение.требовать(type(данные) is dict, 'Неизвестный payload ребёнка')
            тип, вид = запись.get('type'), данные.get('type')
            элемент = данные.get('item')
            вложенный_человек = тип == 'event_msg' and type(элемент) is dict \
                and (элемент.get('type') == 'UserMessage' or элемент.get('role') == 'user')
            хранение.требовать(not (тип == 'event_msg' and вид in {'user_message', 'turn_aborted'}
                or тип == 'response_item' and вид == 'message' and данные.get('role') == 'user'
                or вложенный_человек),
                'Человеческий ввод или отмена требует отдельного разбора координатора')
            if тип == 'event_msg' and type(элемент) is dict \
                    and элемент.get('type') == 'FunctionCallOutput' and элемент.get('name') in снимок.ТРАНСПОРТЫ:
                хранение.требовать(вид == 'item_completed' and not дубль and исходный is not None
                    and элемент.get('namespace') == 'codex_app'
                    and (элемент.get('name'), элемент.get('output')) == исходный,
                    'Подменено, повторено или не подтверждено транспортное завершение поручения')
                дубль = True
            if тип == 'turn_context':
                профиль = попытки[имя]['аргументы']
                хранение.требовать(данные.get('cwd') == слой['корень']
                    and данные.get('model') == профиль['model'] and данные.get('effort') == профиль['thinking'],
                    'Изменён профиль или корень возобновлённого ребёнка')
            if тип == 'response_item' and вид == 'function_call_output' \
                    and данные.get('name') in снимок.ТРАНСПОРТЫ:
                if данные['name'] == 'create_thread':
                    начала += 1
                    хранение.требовать(начала == 1 and not полученные, 'Повторено первоначальное создание ребёнка')
                else:
                    хранение.требовать(начала == 1 and данные['name'] == 'send_message_to_thread'
                        and len(полученные) < len(по_детям[имя]), 'Другой или лишний вход ребёнка')
                    отправка = по_детям[имя][len(полученные)]
                    текст = отправка['аргументы']['prompt']
                    ожидаемый = '<codex_delegation>\n  <source_thread_id>' + исполнитель.задача + '</source_thread_id>\n  <input>' + html.escape(текст, quote=False) + '</input>\n</codex_delegation>'
                    хранение.требовать(данные.get('output') == ожидаемый, 'Полученное поручение не совпало с отправкой корня')
                    полученные.append({'id': отправка['id'], 'получение': {'начало': позиция,
                        'конец': позиция + len(строка), 'sha256': hashlib.sha256(строка).hexdigest()}})
                исходный, дубль = (данные['name'], данные.get('output')), False
            позиция += len(строка)
        хранение.требовать(начала == 1 and len(полученные) == len(по_детям[имя]), 'Не подтверждено получение всех исторических sends')
        for отправка, получение in zip(по_детям[имя], полученные):
            результаты[отправка['id']] = {**перечень[отправка['id']], **получение,
                'отправка': отправка['источник'], 'интервал': отправка['интервал']}
    return результаты

"""Происхождение сохранённой приватной выгрузки без переноса её содержимого."""
import hashlib
import re
import uuid

from снимок_нативного_источника import хранение, ПРЕДЕЛ


def _объект(значение, поля):
    хранение.требовать(type(значение) is dict and set(значение) == set(поля),
                       'Неизвестная рамка выгрузки ответов')


def _хэш(значение):
    хранение.требовать(type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение),
                       'Нужен SHA256')


def _позиция(значение, граница):
    _объект(значение, ('начало', 'конец', 'sha256'))
    хранение.требовать(type(значение['начало']) is int and type(значение['конец']) is int
                       and 0 <= значение['начало'] < значение['конец'] <= граница,
                       'Неверные границы исходной записи')
    _хэш(значение['sha256'])
    return dict(значение)


def свидетельство(сырые, задача):
    хранение.требовать(type(сырые) is bytes and 0 < len(сырые) <= ПРЕДЕЛ, 'Нужна ограниченная выгрузка')
    хранение.требовать(type(задача) is str and str(uuid.UUID(задача)) == задача, 'Нужен UUID задачи')
    данные = хранение.разобрать(сырые)
    _объект(данные, ('схема', 'источник', 'состояние', 'полнота_поддержанных_ответов', 'ответы', 'неопределённости'))
    хранение.требовать(данные['схема'] == 'fum.видимые-ответы-нативной-задачи.1', 'Неизвестная схема выгрузки')
    источник = данные['источник']
    _объект(источник, ('задача', 'граница', 'sha256'))
    хранение.требовать(источник['задача'] == задача and type(источник['граница']) is int
                       and 0 < источник['граница'] <= ПРЕДЕЛ, 'Чужой или неверный источник')
    _хэш(источник['sha256'])
    хранение.требовать(type(данные['ответы']) is list and type(данные['неопределённости']) is list,
                       'Нужны списки ответов и неопределённостей')
    ответы, неопределённости = [], []
    for ответ in данные['ответы']:
        _объект(ответ, ('фаза', 'поле_фазы', 'части', 'исходник', 'сырая_строка'))
        хранение.требовать(type(ответ['фаза']) is str and ответ['фаза'] in {'commentary', 'final'}
                           and type(ответ['поле_фазы']) is str and ответ['поле_фазы'] in {'phase', 'channel'}
                           and type(ответ['части']) is list and ответ['части']
                           and all(type(часть) is str for часть in ответ['части'])
                           and type(ответ['сырая_строка']) is str, 'Неверный сохранённый ответ')
        позиция = _позиция(ответ['исходник'], источник['граница'])
        строка = ответ['сырая_строка'].encode('utf-8')
        хранение.требовать(строка.endswith(b'\n') and len(строка) == позиция['конец'] - позиция['начало']
                           and hashlib.sha256(строка).hexdigest() == позиция['sha256'],
                           'Сохранённая исходная строка повреждена')
        ответы.append({'фаза': ответ['фаза'], 'частей': len(ответ['части']), 'исходник': позиция})
    for неопределённость in данные['неопределённости']:
        _объект(неопределённость, ('исходник', 'причина'))
        неопределённости.append({'исходник': _позиция(неопределённость['исходник'], источник['граница'])})
    состояние = 'неполно' if неопределённости else ('сохранены' if ответы else 'пусто')
    хранение.требовать(данные['состояние'] == состояние
                       and данные['полнота_поддержанных_ответов'] is (not неопределённости),
                       'Противоречивый статус выгрузки')
    return {'схема': 'fum.свидетельство-видимых-ответов.1',
            'выгрузка': {'байтов': len(сырые), 'sha256': hashlib.sha256(сырые).hexdigest()},
            'источник': dict(источник), 'состояние': состояние,
            'полнота_поддержанных_ответов': not неопределённости,
            'ответы': ответы, 'неопределённости': неопределённости, 'содержимое_включено': False}

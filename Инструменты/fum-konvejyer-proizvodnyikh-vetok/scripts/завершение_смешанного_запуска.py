"""Единый терминал сохранённого писателя и не использованного внешним вызовом допуска."""
import copy
import hashlib
from pathlib import Path
import stat

import приём_направления as хранение
from отложенные_назначения import манифест_коммита, извлечь_ответ
import завершение_сохранённых_писателей as сохранённые
import область_писателя
import нативные_вызовы
import последнее_ожидание
import сохранённый_писатель
import терминал_запуска

СХЕМА = 'fum.завершение-неудачного-запуска.4'
КОД = dict(сохранённые.КОД)
КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def _состояние_источника(источник):
    хранение.поля(источник, {'путь', 'начало', 'начало_sha256', 'граница', 'sha256'})
    хранение.требовать(type(источник['путь']) is str and Path(источник['путь']).is_absolute(),
                       'Нужен абсолютный источник координатора')
    путь = Path(источник['путь']); хранение.безопасный_путь(путь)
    сведения = путь.lstat()
    хранение.требовать(stat.S_ISREG(сведения.st_mode), 'Корневой источник должен быть обычным файлом')
    return tuple(getattr(сведения, поле) for поле in
                 ('st_dev', 'st_ino', 'st_size', 'st_mtime_ns', 'st_ctime_ns', 'st_mode'))


def _не_вызван(исполнитель, завершение, попытка, ветка, состояние):
    хранение.поля(завершение, {'вид', 'попытка'})
    хранение.требовать(завершение['вид'] == 'не-вызван'
                       and завершение['попытка'] == попытка['попытка'] and попытка['ответ'] is None,
                       'Нужен невызванный допуск без ответа')
    ветки = хранение.гит(исполнитель.корень, 'for-each-ref', '--format=%(refname)', 'refs/heads/').splitlines()
    хранение.требовать(not any(в.casefold() == ветка.casefold() for в in ветки)
                       and not any(в['ref'].casefold() == ветка.casefold() for в in состояние['писатели'].values()),
                       'Невызванному допуску уже соответствует ветка или писатель')


def _план(исполнитель, вход, состояние):
    хранение.поля(вход, {'схема', 'запуск', 'план_sha256', 'координатор', 'источник',
                        'ожидание', 'слои', 'свидетельство_координатора'})
    хранение.требовать(вход['схема'] == СХЕМА, 'Неизвестный смешанный переход')
    запись = исполнитель._прочитать(состояние, вход['запуск']); план = запись['план']
    наблюдения = запись['наблюдения']
    сохранены = [слой for слой, н in наблюдения.items() if type(н) is dict]
    не_вызваны = [слой for слой, н in наблюдения.items() if н is None]
    хранение.требовать(план['sha256'] == вход['план_sha256']
                       and запись['смысл']['схема'] in {'fum.запуск-двух-слоёв.2', 'fum.запуск-двух-слоёв.3', 'fum.запуск-двух-слоёв.4'}
                       and len(наблюдения) == 2 and len(сохранены) == len(не_вызваны) == 1,
                       'Нужны один наблюдённый писатель и один невызванный допуск')
    слой, пустой = сохранены[0], не_вызваны[0]
    попытки = {имя: состояние['попытки'].get(ключ) for имя, ключ in план['попытки'].items()}
    хранение.требовать(set(попытки) == set(наблюдения), 'Неполный состав попыток')
    история = хранение.хэш({'запись': запись, 'попытки': попытки})
    прежний = терминал_запуска.прочитать(состояние, вход['запуск'])
    if прежний is not None:
        хранение.требовать(прежний['схема'] == терминал_запуска.СХЕМА_СМЕШАННОГО
                           and прежний['вход_sha256'] == хранение.хэш(вход)
                           and прежний['история_sha256'] == история, 'Повтор изменил терминал или историю')
        return copy.deepcopy(прежний), None
    координатор = сохранённые._координатор(исполнитель, вход, план, состояние)
    исполнитель._инструменты(координатор['HEAD'])
    for путь, хэш in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == хэш, 'Код смешанного перехода изменился')
    аттестация = {'задача': исполнитель.задача, 'единственный_координатор': True,
                 'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}
    хранение.требовать(вход['свидетельство_координатора'] == аттестация, 'Нет кооперативной аттестации координатора')
    хранение.требовать(type(вход['слои']) is dict and set(вход['слои']) == set(попытки), 'Неполный состав слоёв')
    база = план['координатор']['HEAD']; смысл = запись['смысл']
    for имя, попытка in попытки.items():
        хранение.требовать(type(попытка) is dict and попытка['аргументы'] == план['аргументы'][имя]
                           and попытка['база'] == база, 'Изменена попытка слоя')
    файлы = манифест_коммита(исполнитель.корень, база, смысл['постановка']['файлы'])
    хранение.требовать(смысл['план'] in файлы and смысл['назначение'] in файлы
                       and хранение.разобрать(файлы[смысл['план']]) == план['описание'], 'Подменён манифест назначения')
    области = область_писателя.каталоги_назначения(исполнитель.корень, база, исполнитель.задача,
        смысл['план'], план['описание'], хранение.разобрать(файлы[смысл['назначение']]))
    ветки = {с['слой']: с['ветка'] for с in план['описание']['слои']}
    _не_вызван(исполнитель, вход['слои'][пустой], попытки[пустой], ветки[пустой], состояние)
    ребёнок = наблюдения[слой]['задача']
    снимок_источника = _состояние_источника(вход['источник'])
    нативный = нативные_вызовы.прочитать(вход['источник'], исполнитель.задача,
        аргументы=[п['аргументы'] for п in попытки.values()], ожидания=[ребёнок], интервалы=True)
    хранение.требовать(_состояние_источника(вход['источник']) == снимок_источника,
                       'Корневой источник изменился во время чтения')
    ожидание = последнее_ожидание.проверить(нативный, вход['ожидание'], [ребёнок])
    вызовы = {имя: [в for в in нативный['вызовы'] if в['аргументы'] == п['аргументы']]
              for имя, п in попытки.items()}
    хранение.требовать(not вызовы[пустой], 'Есть внешний вызов невызванного допуска')
    хранение.требовать(len(вызовы[слой]) == 1
                       and извлечь_ответ(вызовы[слой][0]['ответ']) == попытки[слой]['ответ'],
                       'Нет единственного точного вызова и сохранённого ответа')
    ответ = попытки[слой]['ответ']
    хранение.требовать(not ответ.get('противоречивые_идентификаторы')
                       and ответ.get('threadId') in (None, ребёнок), 'Ответ противоречит ребёнку')
    аргументы = (исполнитель, вход['слои'][слой], наблюдения[слой], попытки[слой], база,
                 области[слой], ветки[слой], ожидание)
    результаты = {слой: сохранённый_писатель.проверить(*аргументы),
                  пустой: {'вид': 'допуск-отозван', 'попытка': попытки[пустой]['попытка'], 'записанных_вызовов': 0}}
    хранение.требовать(сохранённые._координатор(исполнитель, вход, план, состояние) == координатор,
                       'Координатор изменился при проверке')
    квитанция = {'схема': терминал_запуска.СХЕМА_СМЕШАННОГО, 'запуск': вход['запуск'],
        'план_sha256': план['sha256'], 'вход_sha256': хранение.хэш(вход), 'история_sha256': история,
        'координатор': координатор, 'слои': результаты, 'источник': нативный['источник'],
        'ожидание': {к: ожидание[к] for к in ('id', 'источник', 'интервал')},
        'свидетельство_координатора': аттестация, 'отсутствие_незаписанного_вызова_доказано': False}
    return {**квитанция, 'sha256': хранение.хэш(квитанция)}, (слой, аргументы, пустой, попытки[пустой], ветки[пустой], снимок_источника)


def предпросмотр(исполнитель, вход):
    return _план(исполнитель, вход, исполнитель.хранилище.прочитать())[0]


def завершить(исполнитель, вход, ожидаемый_sha256):
    with исполнитель.хранилище.изменить() as состояние:
        результат, сверка = _план(исполнитель, вход, состояние)
        хранение.требовать(результат['sha256'] == ожидаемый_sha256, 'Изменён просмотренный смешанный переход')
        ключ = терминал_запуска.ключ(вход['запуск'])
        if ключ not in состояние['приёмы']:
            слой, аргументы, пустой, попытка, ветка, снимок_источника = сверка
            хранение.требовать(сохранённый_писатель.проверить(*аргументы) == результат['слои'][слой],
                               'Сохранённый писатель изменился перед записью')
            _не_вызван(исполнитель, вход['слои'][пустой], попытка, ветка, состояние)
            исполнитель.хранилище.проверить_владельца_под_замком(состояние,
                ожидаемый_коммит=вход['координатор']['HEAD'], ожидаемая_ветка=вход['координатор']['ref'])
            хранение.требовать(_состояние_источника(вход['источник']) == снимок_источника,
                               'Корневой источник изменился перед терминалом')
            состояние['приёмы'][ключ] = результат
        return copy.deepcopy(результат)

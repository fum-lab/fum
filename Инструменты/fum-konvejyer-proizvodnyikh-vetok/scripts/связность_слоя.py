"""Связность конечной передачи; общий граф ссылок принимает координатор."""
from pathlib import Path

import дочерний_коммит
import приём_направления as хранение
import свежесть_слоя


def проверить(параметры, сообщение, валидатор):
    назначение = дочерний_коммит.проверить(параметры)
    корень = Path(параметры['корень'])
    запрос = корень / параметры['запрос']
    отчёт = запрос.with_name('отчёт.md')
    ошибки = []
    хранение.безопасный_путь(запрос)
    хранение.безопасный_путь(отчёт)
    ошибки.extend(валидатор.validate_request_filename_title(запрос))
    текст = запрос.read_text(encoding='utf-8')
    if not текст.startswith(валидатор.expected_request_heading(запрос) + '\n'):
        ошибки.append('Неверный заголовок собственного запроса')
    навигация = валидатор.section_body(текст, 'Навигация по запросам')
    ожидаемая = '- Предыдущий запрос: отложен до передачи координатору\n- Следующий запрос: отложен до передачи координатору'
    if навигация is None or навигация.strip() != ожидаемая:
        ошибки.append('Неверная отложенная навигация дочерней передачи')
    имена = хранение.гит(корень, 'ls-files', '--cached', '--others', '--exclude-standard', '-z', '--',
        ':(literal)' + назначение['каталоги'][1], сырые=True)
    for имя in (э.decode('utf-8') for э in имена.split(b'\0') if э):
        части = имя.removeprefix(назначение['каталоги'][1]).split('/')
        if части[0] not in {'запрос.md', 'отчёт.md', 'материалы'} or (
                части[0] == 'материалы' and len(части) == 1):
            ошибки.append('Лишний элемент собственной папки запроса: ' + имя)
    ошибки.extend(валидатор.validate_journal(корень, запрос, контрольная_точка=True))
    for путь in (запрос, отчёт):
        ошибки.extend(валидатор.проверить_незаполненный_маркер_шаблона(путь.read_text(encoding='utf-8'), путь, корень))
    ошибки.extend(валидатор.validate_used_tools_section(текст, запрос))
    ошибки.extend(валидатор.validate_codex_commit_context_requirements(запрос, параметры['задача'], сообщение))
    ошибки.extend(валидатор.validate_codex_thread_id_section(текст, запрос, expected_codex_thread_id=параметры['задача']))
    ошибки.extend(валидатор.validate_commit_message_codex_thread_id(текст, запрос, сообщение))
    затронутые, отказ = валидатор.affected_files_from_request(текст, запрос, корень)
    ошибки.extend(отказ)
    if not {запрос, отчёт} <= set(затронутые):
        ошибки.append('В охвате не названа собственная пара запроса и отчёта')
    ошибки.extend(валидатор.validate_git_status(корень, затронутые, None))
    свои = set(свежесть_слоя.markdown(корень, назначение))
    ошибки.extend(валидатор.validate_markdown_links(свои, корень))
    ошибки.extend(валидатор.validate_meta_request_coverage(свои, корень))
    ошибки.extend(валидатор.validate_provenance_section_position(свои, корень))
    ошибки.extend(валидатор.validate_mermaid_markdown_list_labels(свои, корень))
    ошибки.extend(валидатор.validate_answered_question_files(корень, markdown_paths=свои))
    свежесть = свежесть_слоя.подготовить(корень, параметры['исполнитель'], параметры['источник_модели'])
    if свежесть['файлы']:
        ошибки.append('Метки свежести собственной области требуют обновления')
    хранение.требовать(дочерний_коммит.проверить(параметры) == назначение, 'Назначение сдвинулось при проверке связности')
    return ошибки

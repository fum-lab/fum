"""Два первоначальных создания и отдельное последнее ожидание каждого писателя."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import приём_направления as хранение


def предшествует(первое, второе):
    return (первое['источник']['конец'] <= второе['источник']['начало']
            and первое['интервал']['конец_мс'] < второе['интервал']['начало_мс'])


def проверить(нативный, номера, дети):
    хранение.требовать(нативный['схема'] == 'fum.наблюдённые-вызовы-запуска.2'
        and нативный['источник']['начало'] == нативный['начальная_граница'],
        'Нужна полная история с интервалами runtime')
    хранение.требовать(type(дети) is list and len(дети) == 2
        and all(хранение.идентификатор_задачи(д) for д in дети) and len(set(дети)) == 2,
        'Нужны два разных первоначальных писателя')
    хранение.поля(номера, дети)
    хранение.требовать(all(хранение.текст(н) for н in номера.values())
        and len(set(номера.values())) == 2, 'Нужны разные ожидания детей')
    создания = нативный['вызовы']
    хранение.требовать(len(создания) == 2
        and all(с['инструмент'] == 'create_thread' for с in создания)
        and предшествует(создания[0], создания[1]) and нативный['возобновления'] == [],
        'Нужны только два последовательных первоначальных создания')
    выбранные = {}
    for ребёнок, создание in zip(дети, создания):
        адресованные = [о for о in нативный['ожидания']
            if ребёнок in {ц.get('threadId') for ц in о['аргументы']['targets']}]
        хранение.требовать(адресованные and адресованные[-1]['id'] == номера[ребёнок],
            'Нужно последнее адресованное ребёнку ожидание')
        ожидание = адресованные[-1]
        хранение.требовать(len(ожидание['аргументы']['targets']) == 1,
            'Первоначальная передача требует одиночной цели ожидания')
        хранение.требовать(предшествует(создание, ожидание),
            'Первоначальное ожидание началось до собственного создания либо перекрывает его')
        выбранные[ребёнок] = ожидание
    первое_ожидание = выбранные[дети[0]]
    хранение.требовать(предшествует(первое_ожидание, создания[1])
        or предшествует(создания[1], первое_ожидание),
        'Первое ожидание и второе создание пересекаются либо противоречат порядку')
    по_порядку = sorted(выбранные.values(), key=lambda о: о['источник']['начало'])
    первое, второе = по_порядку
    хранение.требовать(первое['источник']['конец'] <= второе['источник']['начало']
        and первое['интервал']['конец_мс'] <= второе['интервал']['начало_мс'],
        'Раздельные первоначальные ожидания должны быть последовательными')
    return выбранные

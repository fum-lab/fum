"""Последние отдельные наблюдения детей после всех воздействий координатора."""
import приём_направления as хранение


def проверить(нативный, номера, дети):
    хранение.требовать(нативный['схема'] == 'fum.наблюдённые-вызовы-запуска.2'
                       and нативный['источник']['начало'] == нативный['начальная_граница'],
                       'Нужна полная история с интервалами runtime')
    хранение.поля(номера, дети)
    хранение.требовать(all(хранение.текст(н) for н in номера.values())
                       and len(set(номера.values())) == len(дети), 'Нужны разные ожидания детей')
    выбранные = {}
    for ребёнок in дети:
        адресованные = [о for о in нативный['ожидания']
                        if ребёнок in {ц.get('threadId') for ц in о['аргументы']['targets']}]
        хранение.требовать(адресованные and адресованные[-1]['id'] == номера[ребёнок],
                           'Нужно последнее адресованное ребёнку ожидание')
        ожидание = адресованные[-1]
        хранение.требовать(len(ожидание['аргументы']['targets']) == 1,
                           'Раздельный переход требует одиночных целей ожидания')
        for воздействие in [*нативный['вызовы'], *нативный['возобновления']]:
            хранение.требовать(воздействие['инструмент'] in {'create_thread', 'send_message_to_thread'},
                               'Перенос задачи не поддержан этим переходом')
            хранение.требовать(воздействие['источник']['конец'] <= ожидание['источник']['начало']
                               and воздействие['интервал']['конец_мс'] < ожидание['интервал']['начало_мс'],
                               'Ожидание началось до завершения воздействия либо перекрывает его')
        выбранные[ребёнок] = ожидание
    порядок = sorted(выбранные.values(), key=lambda о: о['источник']['начало'])
    for первое, второе in zip(порядок, порядок[1:]):
        хранение.требовать(первое['источник']['конец'] <= второе['источник']['начало']
                           and первое['интервал']['конец_мс'] <= второе['интервал']['начало_мс'],
                           'Раздельные ожидания должны быть последовательными')
    return выбранные

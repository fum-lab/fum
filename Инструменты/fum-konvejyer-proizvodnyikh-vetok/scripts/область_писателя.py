"""Читающее описание области из закреплённого назначения и живого наблюдения."""
import hashlib
from pathlib import Path
import re
import unicodedata

import приём_направления as хранение
import постановка_задачи as постановка
from отложенные_назначения import манифест_коммита
import снимок_области

КОД = {Path(имя).resolve(): hashlib.sha256(Path(имя).read_bytes()).hexdigest()
       for имя in (__file__, снимок_области.__file__, снимок_области.охват.__file__, снимок_области.охват.СВЯЗНОСТЬ.__file__)}


def проверить_код():
    for путь, отпечаток in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == отпечаток, "Код области изменён после загрузки")


def каталоги_назначения(корень, база, задача, путь_плана, описание, назначение):
    хранение.поля(назначение, {"схема", "задача", "план", "журналы"})
    хранение.требовать(назначение["схема"] == "fum.назначение-областей-слоёв.1"
                       and назначение["задача"] == задача and назначение["план"] == путь_плана, "Чужое назначение области")
    слои = {э["слой"]: э for э in описание["слои"]}
    журналы = назначение["журналы"]
    хранение.требовать(type(журналы) is dict and set(журналы) == set(слои), "Неверный состав назначенных журналов")
    все = [э["каталог"] for э in слои.values()]
    for имя in журналы.values():
        хранение.требовать(type(имя) is str and re.fullmatch(r"Журнал/\d{4}-\d{2}-\d{2}_\d{2}-\d{2}-\d{2}_MSK_[^/\x00-\x1f]+/", имя),
                           "Нужна точная папка нового Журнала")
        все.append(имя)
    сравнимые = []
    for каталог in все:
        снимок_области.охват.точный_путь(корень, каталог.removesuffix("/"))
        сравнимый = unicodedata.normalize("NFC", каталог).casefold()
        хранение.требовать(not any(сравнимый.startswith(иной) or иной.startswith(сравнимый) for иной in сравнимые), "Области писателей пересекаются")
        сравнимые.append(сравнимый)
    прежние = хранение.гит(корень, "ls-tree", "-r", "--name-only", "-z", база).split("\0")
    for журнал in журналы.values():
        ключ = unicodedata.normalize("NFC", журнал).casefold()
        хранение.требовать(not any(unicodedata.normalize("NFC", имя).casefold().startswith(ключ)
                                   or unicodedata.normalize("NFC", имя).casefold() == ключ[:-1]
                                   for имя in прежние if имя), "Назначенный Журнал уже существовал в C")
    return {имя: [слои[имя]["каталог"], журналы[имя]] for имя in слои}


def описать(исполнитель, ключ, слой, путь_назначения, источник):
    проверить_код()
    состояние = исполнитель.хранилище.прочитать()
    запись = исполнитель._прочитать(состояние, ключ)
    хранение.требовать(слой in запись["наблюдения"] and запись["наблюдения"][слой] is not None,
                       "Нет наблюдённого писателя слоя")
    вход = запись["смысл"]
    if вход["схема"] in {"fum.запуск-двух-слоёв.2", "fum.запуск-двух-слоёв.3"}:
        хранение.требовать(путь_назначения == вход["назначение"], "Назначение отличается от первоначального поручения")
    база = вход["постановка"]["коммит"]
    исполнитель._инструменты(база)
    координатор = исполнитель.хранилище._наблюдать_владельца()
    хранение.требовать(координатор["ref"] == запись["план"]["координатор"]["ref"], "Координатор сменил ветку")
    хранение.гит(исполнитель.корень, "merge-base", "--is-ancestor", база, координатор["HEAD"])
    файлы = манифест_коммита(исполнитель.корень, база, вход["постановка"]["файлы"])
    хранение.требовать(путь_назначения in файлы and вход["план"] in файлы, "Назначение или план отсутствуют в манифесте C")
    описание = хранение.разобрать(файлы[вход["план"]])
    хранение.требовать(описание == запись["план"]["описание"], "План отличается от C")
    области = каталоги_назначения(исполнитель.корень, база, исполнитель.задача, вход["план"], описание,
                                  хранение.разобрать(файлы[путь_назначения]))
    наблюдение = запись["наблюдения"][слой]
    хранение.требовать(наблюдение["задача"] != исполнитель.задача, "UUID исполнителя совпал с корневой задачей")
    дерево = Path(наблюдение["корень"])
    попытка = состояние["попытки"].get(запись["план"]["попытки"][слой])
    хранение.требовать(type(попытка) is dict, "Нет попытки наблюдённого писателя")
    кодирование = "xml-v1" if вход["схема"] in {"fum.запуск-двух-слоёв.2", "fum.запуск-двух-слоёв.3"} else "буквальный"
    def перечитать():
        return {**постановка.прочитать_подтверждение(дерево, наблюдение["задача"], база, источник),
                "поручение": постановка.проверить_нативное_поручение(
                    источник, исполнитель.задача, попытка["аргументы"]["prompt"], кодирование=кодирование)}
    хранение.требовать(перечитать() == наблюдение, "Изменилось первичное наблюдение писателя")
    снимок = снимок_области.снимок(дерево, наблюдение["задача"], база, области[слой])
    ожидаемый_ref = next(э["ветка"] for э in описание["слои"] if э["слой"] == слой)
    хранение.требовать(снимок["владелец"]["ref"] == ожидаемый_ref and дерево != исполнитель.корень, "Чужая ветка или общее дерево")
    результат = {"схема": "fum.наблюдённая-область-писателя.1", "запуск": ключ, "слой": слой,
                 "корневая_задача": исполнитель.задача, "база": база, "писатель": снимок["владелец"],
                 "назначение": {"путь": путь_назначения, "sha256": hashlib.sha256(файлы[путь_назначения]).hexdigest()},
                 "наблюдение_sha256": хранение.хэш(наблюдение), "каталоги": области[слой],
                 "снимок": снимок, "разрешение_записи": False}
    хранение.требовать(перечитать() == наблюдение
                       and снимок_области.снимок(дерево, наблюдение["задача"], база, области[слой]) == снимок
                       and исполнитель.хранилище.прочитать() == состояние
                       and исполнитель.хранилище._наблюдать_владельца() == координатор, "Состояние сдвинулось во время экспорта")
    проверить_код()
    return {**результат, "sha256": хранение.хэш(результат)}

"""Явная цепочка преемников с сохранением каждой прежней попытки."""
import re
import unicodedata

import приём_направления as хранение
import терминал_запуска


def полное_поручение(пакет):
    return пакет.get("схема") in {"fum.запуск-двух-слоёв.2", "fum.запуск-двух-слоёв.3", "fum.запуск-двух-слоёв.4"}


def ссылка(значение):
    хранение.поля(значение, {"запуск", "терминал_sha256"})
    хранение.требовать(all(type(в) is str and re.fullmatch(r"[0-9a-f]{64}", в)
                           for в in значение.values()), "Неполная ссылка на завершённый запуск")
    return значение


def проверить_версию_плана(пакет, описание):
    версия = пакет.get('схема')
    хранение.требовать(версия in {'fum.запуск-двух-слоёв.' + str(ч) for ч in (1, 2, 3, 4)}, 'Неизвестная версия запуска')
    новый = версия == 'fum.запуск-двух-слоёв.4'
    с_предком = версия in {'fum.запуск-двух-слоёв.3', 'fum.запуск-двух-слоёв.4'}
    предыдущий = пакет.get('предыдущий')
    хранение.требовать((предыдущий is not None) == с_предком, 'Неверное поколение сохранённого запуска')
    хранение.требовать(описание['схема'] == ('fum.план-запуска-двух-слоёв.2' if новый else 'fum.план-запуска-двух-слоёв.1'),
                       'Версия плана не соответствует версии запуска')
    if с_предком:
        ссылка(предыдущий)
    if новый:
        хранение.требовать(описание['предыдущий'] == предыдущий, 'План закрепляет другого предшественника')
    return новый


def логический_план(описание):
    return {'конвейер': описание['конвейер'], 'шаг': описание['шаг'],
            'слои': [{**{к: с[к] for к in ('слой', 'каталог', 'роль')}, 'зависит_от': sorted(с['зависит_от'])}
                     for с in sorted(описание['слои'], key=lambda с: с['слой'])]}


def пересекаются(первый, второй):
    def пути(план):
        return [unicodedata.normalize('NFC', с['каталог']).casefold() for с in план['слои']]
    return any(а.startswith(б) or б.startswith(а) for а in пути(первый) for б in пути(второй))


def предки(исполнитель, состояние, предыдущий, описание, новый_C, *, новые_ветки=False):
    """Освободить резервирование только у проверенных предков этого запуска."""
    проверенные = set()
    while предыдущий is not None:
        ссылка(предыдущий)
        ключ = предыдущий["запуск"]
        хранение.требовать(ключ not in проверенные, "Цикл поколений запуска")
        запись = исполнитель._прочитать(состояние, ключ)
        план = запись["план"]
        совпал = логический_план(план['описание']) == логический_план(описание) if новые_ветки else план['описание'] == описание
        хранение.требовать(полное_поручение(запись["смысл"]) and совпал,
                           "Чужой состав предшествующего запуска")
        терминал = терминал_запуска.прочитать(состояние, ключ)
        хранение.требовать(терминал is not None, "Предшествующий запуск ещё не завершён")
        попытки = {слой: состояние["попытки"].get(к) for слой, к in план["попытки"].items()}
        хранение.требовать(терминал["sha256"] == предыдущий["терминал_sha256"]
                           and терминал["план_sha256"] == план["sha256"]
                           and терминал["история_sha256"] == хранение.хэш({"запись": запись, "попытки": попытки}),
                           "Изменён терминал или история предшественника")
        координатор = терминал["координатор"]
        хранение.требовать(координатор["задача"] == исполнитель.задача
                           and координатор["путь"] == str(исполнитель.корень), "Чужой координатор терминала")
        хранение.гит(исполнитель.корень, "merge-base", "--is-ancestor", координатор["HEAD"], новый_C)
        проверенные.add(ключ)
        предыдущий = запись["смысл"].get("предыдущий")
    return проверенные

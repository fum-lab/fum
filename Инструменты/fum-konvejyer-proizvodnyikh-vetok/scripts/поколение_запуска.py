"""Явная цепочка преемников с сохранением каждой прежней попытки."""
import re

import приём_направления as хранение
import терминал_запуска


def полное_поручение(пакет):
    return пакет.get("схема") in {"fum.запуск-двух-слоёв.2", "fum.запуск-двух-слоёв.3"}


def ссылка(значение):
    хранение.поля(значение, {"запуск", "терминал_sha256"})
    хранение.требовать(all(type(в) is str and re.fullmatch(r"[0-9a-f]{64}", в)
                           for в in значение.values()), "Неполная ссылка на завершённый запуск")
    return значение


def предки(исполнитель, состояние, предыдущий, описание, новый_C):
    """Освободить резервирование только у проверенных предков этого запуска."""
    проверенные = set()
    while предыдущий is not None:
        ссылка(предыдущий)
        ключ = предыдущий["запуск"]
        хранение.требовать(ключ not in проверенные, "Цикл поколений запуска")
        запись = исполнитель._прочитать(состояние, ключ)
        план = запись["план"]
        хранение.требовать(полное_поручение(запись["смысл"]) and план["описание"] == описание,
                           "Чужой состав предшествующего запуска")
        терминал = терминал_запуска.прочитать(состояние, ключ)
        хранение.требовать(терминал is not None, "Предшествующий запуск ещё не завершён")
        попытки = {слой: состояние["попытки"].get(к) for слой, к in план["попытки"].items()}
        хранение.требовать(терминал["sha256"] == предыдущий["терминал_sha256"]
                           and терминал["план_sha256"] == план["sha256"]
                           and терминал["история_sha256"] == хранение.хэш({"запись": запись, "попытки": попытки}),
                           "Изменён терминал или история предшественника")
        координатор = терминал["координатор"]
        хранение.требовать(координатор["задача"] == исполнитель.задача
                           and координатор["путь"] == str(исполнитель.корень), "Чужой координатор терминала")
        хранение.гит(исполнитель.корень, "merge-base", "--is-ancestor", координатор["HEAD"], новый_C)
        проверенные.add(ключ)
        предыдущий = запись["смысл"].get("предыдущий")
    return проверенные

СХЕМА_ЗАПИСИ = "fum.сохранённый-запуск-двух-слоёв.1"
КОД = {Path(имя).resolve(): hashlib.sha256(Path(имя).read_bytes()).hexdigest()
       for имя in (__file__, поручение_слоя.__file__, план_запуска_слоёв.__file__, паспорт_конвейера.__file__,
                   хранение.__file__, приём.__file__, вход.__file__, постановка.__file__, назначения.__file__, терминал_запуска.__file__, поколение_запуска.__file__)}


def смысл(пакет):
    return {ключ: приём.смысл_решения(значение) if ключ == "решение" else copy.deepcopy(значение)
            for ключ, значение in пакет.items() if ключ != "источник"}


def ключ_запуска(задача, план, предыдущий=None):
    if предыдущий is not None:
        return хранение.хэш({"схема": "fum.ключ-запуска-слоёв.2", "задача": задача,
                             "конвейер": план["конвейер"], "шаг": план["шаг"],
                             "предыдущий": поколение_запуска.ссылка(предыдущий)})
    return хранение.хэш({"схема": "fum.ключ-запуска-слоёв.1", "задача": задача,
                         "конвейер": план["конвейер"], "шаг": план["шаг"]})


class ИсполнительЗапускаСлоёв:
    def __init__(сам, корень, задача):
        сам.хранилище = хранение.Хранилище(корень, задача)
        сам.корень, сам.задача = сам.хранилище.корень, задача

    def _инструменты(сам, коммит):
        приём.проверить_инструменты(сам.корень, коммит)
        for путь, отпечаток in КОД.items():
            хранение.безопасный_путь(путь)
            хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == отпечаток,
                               "Код запуска слоёв изменён после загрузки")

    def _прочитать(сам, состояние, ключ):
        запись = состояние["приёмы"].get(ключ)
        хранение.поля(запись, {"схема", "смысл", "план", "наблюдения"})
        хранение.требовать(запись["схема"] == СХЕМА_ЗАПИСИ, "Неизвестная запись запуска")
        план = запись["план"]
        хранение.поля(план, {"запуск", "описание", "попытки", "координатор", "аргументы", "наблюдения", "смысл_sha256", "sha256"})
        описание = проверить_план(план["описание"])
        имена = {слой["слой"] for слой in описание["слои"]}
        предыдущий = запись["смысл"].get("предыдущий")
        хранение.требовать((предыдущий is not None) == (запись["смысл"].get("схема") == "fum.запуск-двух-слоёв.3"),
                           "Неверное поколение сохранённого запуска")
        хранение.требовать(план["запуск"] == ключ == ключ_запуска(сам.задача, описание, предыдущий)
                           and план["координатор"]["задача"] == сам.задача
                           and план["координатор"]["путь"] == str(сам.корень), "Чужая идентичность запуска")
        хранение.требовать(план["sha256"] == хранение.хэш({k: v for k, v in план.items() if k != "sha256"})
                           and план["смысл_sha256"] == хранение.хэш(запись["смысл"]), "Повреждён план запуска")
        хранение.требовать(set(запись["наблюдения"]) == имена == set(план["попытки"]) == set(план["аргументы"])
                           and план["наблюдения"] == dict.fromkeys(имена), "Неверный состав сохранённых слоёв")
        return запись

    def _план(сам, пакет, состояние):
        версия2 = type(пакет) is dict and поколение_запуска.полное_поручение(пакет)
        версия3 = type(пакет) is dict and пакет.get("схема") == "fum.запуск-двух-слоёв.3"
        хранение.поля(пакет, {"схема", "задача", "постановка", "план", "проект", "источник", "решение"}
                       | ({"назначение"} if версия2 else set()) | ({"предыдущий"} if версия3 else set()))
        хранение.требовать(пакет["схема"] in {"fum.запуск-двух-слоёв.1", "fum.запуск-двух-слоёв.2", "fum.запуск-двух-слоёв.3"} and пакет["задача"] == сам.задача
                           and хранение.текст(пакет["проект"]), "Чужой либо неполный пакет запуска")
        закреплено = постановка.проверить_постановку(сам.корень, пакет["постановка"])
        файлы = манифест_коммита(сам.корень, закреплено["коммит"], закреплено["файлы"])
        хранение.требовать(пакет["план"] in файлы, "План не входит в точный манифест")
        описание = проверить_план(хранение.разобрать(файлы[пакет["план"]]))
        предыдущий = пакет.get("предыдущий")
        if версия3:
            поколение_запуска.ссылка(предыдущий)
        предки = поколение_запуска.предки(сам, состояние, предыдущий, описание, закреплено["коммит"]) if версия3 else set()
        ключ = ключ_запуска(сам.задача, описание, предыдущий)
        терминал_запуска.требовать_открытый(состояние, ключ)
        if ключ in состояние["приёмы"]:
            запись = сам._прочитать(состояние, ключ)
            хранение.требовать(запись["смысл"] == смысл(пакет), "Изменён неизменяемый запуск, включая C или состав")
        for другой_ключ, другая in состояние["приёмы"].items():
            if другой_ключ != ключ and другой_ключ not in предки and type(другая) is dict and другая.get("схема") == СХЕМА_ЗАПИСИ:
                занятые = {s["ветка"] for s in другая["план"]["описание"]["слои"]}
                хранение.требовать(not занятые.intersection(s["ветка"] for s in описание["слои"]), "Слой уже назначен другим запуском")
        сам._инструменты(закреплено["коммит"])
        if версия2:
            from область_писателя import каталоги_назначения, проверить_код
            проверить_код()
            хранение.путь_результата(пакет["назначение"])
            обязательные = {пакет["план"], пакет["назначение"]} | {э["поручение"] for э in описание["слои"]}
            хранение.требовать(обязательные <= set(файлы), "Сокращён манифест первоначального назначения")
            каталоги_назначения(сам.корень, закреплено["коммит"], сам.задача, пакет["план"], описание,
                               хранение.разобрать(файлы[пакет["назначение"]]))
        хранение.требовать(type(пакет["решение"]) is dict and type(пакет["решение"].get("задача")) is dict
                           and пакет["решение"]["задача"].get("режим") == "создать", "Нет решения о создании отдельных задач")
        хранение.требовать(пакет["решение"]["задача"].get("projectId") == пакет["проект"], "Проект отличается от подтверждаемого решения")
        вход.проверить_решение(сам.корень, пакет["источник"], сам.задача, пакет["решение"])
        координатор = сам.хранилище._наблюдать_владельца()
        хранение.требовать(координатор["HEAD"] == закреплено["коммит"] and координатор["ref"] == закреплено["ветка"],
                           "Координатор сдвинулся от постановки")
        аргументы, попытки = {}, {}
        for слой in описание["слои"]:
            имя = слой["слой"]
            хранение.гит(сам.корень, "check-ref-format", слой["ветка"])
            хранение.требовать(слой["поручение"] in файлы and файлы[слой["поручение"]].strip(), "Нет сохранённого поручения слоя")
            текст = поручение_слоя.сформировать(файлы[слой["поручение"]].decode("utf-8"), слой, закреплено["коммит"],
                                              поручение_слоя.блок(пакет, имя) if версия2 else None)
            аргументы[имя] = {"model": "gpt-6-astra", "thinking": "low", "title": слой["роль"], "prompt": текст,
                               "target": {"type": "project", "projectId": пакет["проект"], "environment": {"type": "worktree", "startingState": закреплено["startingState"]}}}
            попытки[имя] = хранение.хэш({"запуск": ключ, "слой": имя})
        план = {"запуск": ключ, "описание": описание, "попытки": попытки, "координатор": координатор,
                "аргументы": аргументы, "наблюдения": dict.fromkeys(попытки), "смысл_sha256": хранение.хэш(смысл(пакет))}
        return {**план, "sha256": хранение.хэш(план)}

    def предпросмотр(сам, пакет):
        return сам._план(пакет, сам.хранилище.прочитать())

    def подготовить(сам, пакет, ожидаемый_sha256):
        план = сам.предпросмотр(пакет)
        хранение.требовать(план["sha256"] == ожидаемый_sha256, "Изменён просмотренный план")
        сам.хранилище.занять()
        with сам.хранилище.изменить() as состояние:
            хранение.требовать(сам._план(пакет, состояние) == план, "План сдвинулся под замком")
            сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемая_ветка=план["координатор"]["ref"], ожидаемый_коммит=план["координатор"]["HEAD"])
            ключ = план["запуск"]
            if ключ not in состояние["приёмы"]:
                состояние["приёмы"][ключ] = {"схема": СХЕМА_ЗАПИСИ, "смысл": смысл(пакет), "план": план, "наблюдения": dict.fromkeys(план["попытки"])}
        return план

    def допустить(сам, пакет, слой):
        план = сам.предпросмотр(пакет)
        запись = сам._прочитать(сам.хранилище.прочитать(), план["запуск"])
        хранение.требовать(план == запись["план"] and слой in план["попытки"], "Неизвестный слой либо изменённый план")
        def допуск(состояние):
            текущая = сам._прочитать(состояние, план["запуск"])
            хранение.требовать(сам._план(пакет, состояние) == текущая["план"], "План изменён перед внешним вызовом")
            сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемый_коммит=план["координатор"]["HEAD"], ожидаемая_ветка=план["координатор"]["ref"])
            ожидаемая = next(s["ветка"] for s in план["описание"]["слои"] if s["слой"] == слой).casefold()
            ветки = хранение.гит(сам.корень, "for-each-ref", "--format=%(refname)", "refs/heads/").splitlines()
            хранение.требовать(not any(ожидаемая == ref.casefold() or ожидаемая.startswith(ref.casefold() + "/")
                                       or ref.casefold().startswith(ожидаемая + "/") for ref in ветки), "Ветка слоя занята либо конфликтует с существующим ref")
        попытка = сам.хранилище.начать_попытку(план["попытки"][слой], план["аргументы"][слой], проверить_допуск=допуск)
        return {**попытка, "запуск": план["запуск"], "слой": слой}

    def сохранить(сам, ключ, слой, попытка, ответ):
        состояние = сам.хранилище.прочитать()
        терминал_запуска.требовать_открытый(состояние, ключ)
        запись = сам._прочитать(состояние, ключ)
        хранение.требовать(слой in запись["план"]["попытки"], "Неизвестный слой")
        разобранный = извлечь_ответ(ответ)
        def допуск(состояние):
            терминал_запуска.требовать_открытый(состояние, ключ)
            наблюдение = сам._прочитать(состояние, ключ)["наблюдения"][слой]
            if наблюдение is not None:
                хранение.требовать(not разобранный.get("противоречивые_идентификаторы")
                                   and разобранный.get("threadId") in (None, наблюдение["задача"]), "Поздний ответ противоречит наблюдённой задаче")
        return сам.хранилище.сохранить_ответ(запись["план"]["попытки"][слой], попытка, разобранный, проверить_допуск=допуск)

    def наблюдать(сам, ключ, слой, корень_ребёнка, задача, источник):
        with сам.хранилище.изменить() as состояние:
            терминал_запуска.требовать_открытый(состояние, ключ)
            запись = сам._прочитать(состояние, ключ)
            сам.хранилище.проверить_владельца_под_замком(состояние, ожидаемая_ветка=запись["план"]["координатор"]["ref"])
            хранение.требовать(слой in запись["план"]["попытки"], "Неизвестный слой")
            попытка = состояние["попытки"].get(запись["план"]["попытки"][слой])
            хранение.требовать(попытка is not None, "Нет внешней попытки слоя")
            ответ = попытка["ответ"] or {}
            хранение.требовать(not ответ.get("противоречивые_идентификаторы") and ответ.get("threadId") in (None, задача), "Наблюдение противоречит полному ответу")
            кодирование = "xml-v1" if поколение_запуска.полное_поручение(запись["смысл"]) else "буквальный"
            поручение = постановка.проверить_нативное_поручение(
                источник, сам.задача, попытка["аргументы"]["prompt"], кодирование=кодирование)
            результат = {**постановка.прочитать_подтверждение(Path(корень_ребёнка), задача, запись["смысл"]["постановка"]["коммит"], источник), "поручение": поручение}
            хранение.требовать(not поколение_запуска.полное_поручение(запись["смысл"]) or результат["схема"] == "fum.начальная-база-задачи.2",
                               "Нет раннего подтверждения полного поручения v2")
            ожидаемый = next(s for s in запись["план"]["описание"]["слои"] if s["слой"] == слой)
            хранение.требовать(результат["ref"] == ожидаемый["ветка"] and результат["корень"] != str(сам.корень), "Чужая ветка либо общее дерево")
            for иной, наблюдение in запись["наблюдения"].items():
                if иной != слой and наблюдение is not None:
                    хранение.требовать(наблюдение["задача"] != задача and наблюдение["корень"] != результат["корень"], "Одна задача или дерево назначены двум слоям")
            хранение.требовать(запись["наблюдения"][слой] in (None, результат), "Прежнее наблюдение изменилось")
            запись["наблюдения"][слой] = результат
            return copy.deepcopy(результат)

    def состояние(сам, ключ):
        состояние = сам.хранилище.прочитать()
        запись = сам._прочитать(состояние, ключ)
        return {"запуск": ключ, "наблюдения": copy.deepcopy(запись["наблюдения"]),
                "попытки": {слой: copy.deepcopy(состояние["попытки"].get(событие)) for слой, событие in запись["план"]["попытки"].items()}}

    def область(сам, ключ, слой, назначение, источник):
        try:
            import область_писателя
        except (ImportError, OSError) as ошибка:
            raise хранение.ОшибкаПриёма("Недоступна зависимость экспорта области") from ошибка
        return область_писателя.описать(сам, ключ, слой, назначение, источник)

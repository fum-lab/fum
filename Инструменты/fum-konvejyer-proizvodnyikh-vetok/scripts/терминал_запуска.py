"""Неизменяемая конечная запись отдельно от исходных попыток запуска."""
import приём_направления as хранение

СХЕМА = "fum.завершённый-неудачный-запуск.1"
СХЕМА_С_ПАКЕТАМИ = "fum.завершённый-неудачный-запуск.2"
СХЕМА_РАЗДЕЛЬНЫХ_ОЖИДАНИЙ = "fum.завершённый-неудачный-запуск.3"
СХЕМА_СМЕШАННОГО = "fum.завершённый-неудачный-запуск.4"
СХЕМА_ДВУХ_ДО_ЗАПИСИ = "fum.завершённый-неудачный-запуск.5"
СХЕМА_ОДНОГО_ДО_ЗАПИСИ = "fum.завершённый-неудачный-запуск.6"
СХЕМА_СМЕШАННОГО_СОЗДАНИЯ = "fum.завершённый-неудачный-запуск.7"
СХЕМА_СОХРАНЁННОЙ_ПОСТАВКИ = "fum.завершённый-неудачный-запуск.8"
СХЕМА_ОТКАЗАВШЕГО_ПРИЁМА = "fum.завершённый-неудачный-запуск.9"


def ключ(запуск):
    return хранение.хэш({"схема": СХЕМА, "запуск": запуск})


def прочитать(состояние, запуск):
    запись = состояние["приёмы"].get(ключ(запуск))
    if запись is not None:
        хранение.требовать(type(запись) is dict and запись.get("схема") in {СХЕМА, СХЕМА_С_ПАКЕТАМИ, СХЕМА_РАЗДЕЛЬНЫХ_ОЖИДАНИЙ, СХЕМА_СМЕШАННОГО, СХЕМА_ДВУХ_ДО_ЗАПИСИ, СХЕМА_ОДНОГО_ДО_ЗАПИСИ, СХЕМА_СМЕШАННОГО_СОЗДАНИЯ, СХЕМА_СОХРАНЁННОЙ_ПОСТАВКИ, СХЕМА_ОТКАЗАВШЕГО_ПРИЁМА}
                           and запись.get("запуск") == запуск and запись.get("sha256")
                           == хранение.хэш({к: в for к, в in запись.items() if к != "sha256"}),
                           "Повреждён терминал запуска")
    return запись


def требовать_открытый(состояние, запуск):
    хранение.требовать(прочитать(состояние, запуск) is None, "Запуск уже завершён; поздняя мутация запрещена")

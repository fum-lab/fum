"""Неизменяемая конечная запись отдельно от исходных попыток запуска."""
import приём_направления as хранение

СХЕМА = "fum.завершённый-неудачный-запуск.1"


def ключ(запуск):
    return хранение.хэш({"схема": СХЕМА, "запуск": запуск})


def прочитать(состояние, запуск):
    запись = состояние["приёмы"].get(ключ(запуск))
    if запись is not None:
        хранение.требовать(type(запись) is dict and запись.get("схема") == СХЕМА
                           and запись.get("запуск") == запуск and запись.get("sha256")
                           == хранение.хэш({к: в for к, в in запись.items() if к != "sha256"}),
                           "Повреждён терминал запуска")
    return запись


def требовать_открытый(состояние, запуск):
    хранение.требовать(прочитать(состояние, запуск) is None, "Запуск уже завершён; поздняя мутация запрещена")

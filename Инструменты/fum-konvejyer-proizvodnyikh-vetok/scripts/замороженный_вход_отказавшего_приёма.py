"""Связать сохранённый вход и нативное основание с независимо прочитанным живым потоком."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import конверт_приёма as конверт
import эпизод_приёма as эпизод
import нативный_приём as транспорт
import снимок_нативного_источника as снимок
import полный_поток_передачи as полный
from приватные_файлы_отказа import СнимокФайлов

хранение = эпизод.хранение


def _равно(левое, правое, причина):
    хранение.требовать(хранение.байты(левое) == хранение.байты(правое), причина)


def проверить(пакет, текст, сырые, идентичность, живой_источник, прежнее_ожидание,
        отправка, связь, файловая, цель, *, сверки=None):
    блок = конверт.разобрать_текст(текст)
    каталог = конверт.адрес(текст, получатель=True)
    файлы = СнимокФайлов()
    прочитать = lambda имя, путь, **параметры: файлы.прочитать(
        имя, каталог / путь, конверт.КОРЕНЬ_СОСТОЯНИЯ, **параметры)
    сохранённый_конверт = прочитать('конверт', 'конверт.json')
    _равно(сохранённый_конверт, пакет, 'Получатель сохранил другой конверт')
    вход = прочитать('вход', 'вход.json')
    поручение = прочитать('поручение', 'поручение.txt', json=False)
    хранение.требовать(поручение == текст.encode('utf-8'), 'Сохранён другой текст поручения')
    описание = прочитать('описание', 'нативный/описание.json')
    замороженные = прочитать('нативный', 'нативный/источник.jsonl', json=False, предел=снимок.ПРЕДЕЛ)
    хранение.поля(описание, {'схема', 'задача', 'источник', 'идентичность', 'граница', 'sha256'})
    хранение.требовать(описание['схема'] == 'fum.снимок-нативного-источника.1'
        and описание['задача'] == блок['исполнитель']
        and описание['источник'] == живой_источник
        and type(описание['идентичность']) is list and len(описание['идентичность']) == 2
        and all(type(к) is int and к >= 0 for к in описание['идентичность'])
        and описание['идентичность'] == идентичность,
        'Замороженный вход принадлежит другому живому источнику')
    хранение.требовать(type(описание['граница']) is int
        and 0 < описание['граница'] == len(замороженные) <= цель['начало']
        and замороженные.endswith(b'\n')
        and hashlib.sha256(замороженные).hexdigest() == описание['sha256']
        and сырые.startswith(замороженные), 'Изменён замороженный вход или его живой префикс')
    файлы.состав(каталог / 'нативный', {'описание.json', 'источник.jsonl'})
    снимок._модель(замороженные, блок['исполнитель'])
    описание_пакета = прочитать('пакет', 'пакет.json')
    _равно(описание_пакета, {'схема': 'fum.приватный-вход-приёма.1',
        'конверт_sha256': хранение.хэш(пакет), 'вход_sha256': хранение.хэш(вход),
        'снимок_sha256': хранение.хэш(описание)}, 'Подменён пакет замороженного входа')
    свидетельство = пакет['свидетельство']
    получено = транспорт.прочитать_байты_входа(замороженные, свидетельство['остановка'],
        блок['корневая_задача'], блок['исполнитель'], блок['корень'], текст)
    _равно(получено, связь['получение'], 'Замороженное и живое получение различаются')
    полный.проверить(замороженные, получено['конец'], транспорт='send_message_to_thread')
    ожидаемое = {'схема': 'fum.нативный-приём.1', 'корневая_задача': блок['корневая_задача'],
        'исполнитель': блок['исполнитель'], 'текст': текст, 'остановленный_ход': связь['прежний_ход'],
        'ожидание': прежнее_ожидание['источник'], 'отправка': отправка['источник'],
        'свидетельство_sha256': хранение.хэш(свидетельство), 'получение': получено,
        'граница': 'Наблюдённый нативный транспорт; разрешение записи проверяется отдельно'}
    ключ = хранение.хэш({к: блок[к] for к in ('назначение_sha256', 'исполнитель')})
    намерение = файлы.прочитать('намерение', эпизод._путь_ключа(блок['исполнитель'], ключ),
        эпизод.КОРЕНЬ_СОСТОЯНИЯ)
    _равно(намерение['данные']['основание']['нативный_приём'], ожидаемое,
        'Сохранённое нативное основание не совпало с первичным транспортом')
    хэши = файлы.сверить()
    _равно({к: хэши[к] for к in ('конверт', 'вход', 'намерение')},
        {к: файловая['файлы_sha256'][к] for к in ('конверт', 'вход', 'намерение')},
        'Файловое основание сдвинулось после первой проверки')
    if сверки is not None: сверки.сохранить_сверку(файлы.сверить)
    return {'схема': 'fum.проверенный-замороженный-вход-отказа.1',
        'файлы_sha256': хэши, 'нативное_основание_sha256': хранение.хэш(ожидаемое),
        'получение': получено, 'повтор_эффекта_разрешён': False}

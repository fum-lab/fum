"""Закрытый вход получателя: первичные данные и вычисляемые приватные адреса."""
import hashlib
import os
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import эпизод_приёма as эпизод
import приём_интеграции
import план_журнала_приёма as план
import создание_коммита as коммит

хранение = эпизод.хранение


def прочитать(файл, корень):
    данные = хранение.разобрать(коммит.прочитать(Path(файл), приватный=True))
    хранение.поля(данные, {'схема', 'источник', 'текст', 'план', 'свидетельство', 'реестр', 'коммит'})
    хранение.требовать(данные['схема'] == 'fum.вход-дочернего-приёма.1', 'Неизвестная схема входа приёма')
    хранение.поля(данные['коммит'], {'имя_автора', 'заголовок', 'описание'})
    for значение in данные['коммит'].values():
        хранение.требовать(хранение.текст(значение) and '\0' not in значение, 'Нужны текстовые поля коммита')
    хранение.требовать(коммит.проверить_роль(данные['коммит']['имя_автора']), 'Неверный формат роли автора')
    текст = данные['текст']
    хранение.требовать(type(текст) is str and текст.startswith(приём_интеграции.НАЧАЛО)
        and текст.endswith(приём_интеграции.КОНЕЦ), 'Нужен полный текст поручения')
    блок = хранение.разобрать(текст[len(приём_интеграции.НАЧАЛО):-len(приём_интеграции.КОНЕЦ)].encode('utf-8'))
    хранение.требовать(приём_интеграции.сформировать(блок) == текст
        and блок['исполнитель'] == os.environ.get('CODEX_THREAD_ID')
        and блок['корень'] == str(корень), 'Поручение не совпало с нативным исполнителем и физическим корнем')
    return данные, блок



"""Проверенный единственный H сохраняется без повторного создания или интеграции."""
from pathlib import Path
import hashlib

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import приём_направления as хранение
import создание_коммита as коммит
import остановка_ребёнка
import снимок_области
import привязка_писателя_для_координатора as привязка


def _свидетельство(описание):
    хранение.поля(описание, {'путь', 'sha256'})
    хранение.требовать(хранение.шестнадцатеричный(описание['sha256']), 'Нужен SHA приватного свидетельства')
    данные = коммит.прочитать(описание['путь'], приватный=True)
    хранение.требовать(коммит.хэш(данные) == описание['sha256'], 'Подменено приватное свидетельство коммита')
    return хранение.разобрать(данные)


def проверить(исполнитель, вход, запись, наблюдение, попытка, база, каталоги, ветка, ожидание):
    хранение.поля(вход, {'вид', 'попытка', 'задача', 'корень', 'источник', 'подготовка', 'квитанция'})
    хранение.требовать(вход['вид'] == 'остановлен-с-коммитом'
        and вход['попытка'] == попытка['попытка'] and вход['задача'] == наблюдение['задача']
        and вход['корень'] == наблюдение['корень'] and вход['задача'] != исполнитель.задача,
        'Чужой остановленный писатель с коммитом')
    корень = Path(вход['корень'])
    хранение.требовать(корень.is_absolute() and корень == корень.resolve() and корень != исполнитель.корень
        and Path(хранение.гит(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').strip())
            == исполнитель.хранилище.общий, 'Нужен отдельный ребёнок той же Git-базы')
    записи = остановка_ребёнка.снимок(вход['источник'])
    ход = остановка_ребёнка.подтвердить_ход(записи, вход['задача'], ожидание, True, корень=str(корень))
    основание, поручение = привязка.проверить(
        исполнитель, запись, 'события', попытка, наблюдение, вход['источник'], каталоги, ветка)
    подготовка = _свидетельство(вход['подготовка']); квитанция = _свидетельство(вход['квитанция'])
    хранение.поля(подготовка, {'схема', 'параметры', 'имя_автора', 'готовность', 'команды', 'модель',
        'наблюдений', 'история_sha256', 'сообщение_sha256', 'исходный_автор', 'исходный_коммиттер', 'явные_даты'})
    хранение.поля(квитанция, {'схема', 'состояние', 'ожидание', 'подготовка_sha256', 'проверки',
        'допуск', 'готовность', 'индекс_sha256', 'подготовка_наносекунды', 'профиль', 'процесс',
        'наблюдённый_коммит', 'результат'})
    параметры = подготовка['параметры']
    хранение.поля(параметры, {'схема', 'корень', 'ветка', 'исходный_коммит', 'родители', 'задача',
        'имя_автора', 'запрос', 'источник_модели', 'кэш_модели', 'история_модели', 'источники', 'заголовок',
        'описание', 'сообщение', 'подготовка', 'квитанция', 'режим', 'разрешённые_цели', 'исполнитель', 'назначение_sha256'})
    хранение.требовать(подготовка['схема'] == 'fum.подготовленный-коммит.5'
        and параметры['схема'] == 'fum.создание-коммита.3' and параметры['режим'] == 'дочерняя-передача'
        and параметры['корень'] == str(корень) and параметры['ветка'] == ветка
        and параметры['задача'] == исполнитель.задача and параметры['исполнитель'] == вход['задача']
        and параметры['исходный_коммит'] == база and параметры['родители'] == [база]
        and параметры['источник_модели'] == вход['источник']['путь'] and параметры['источники'] == []
        and параметры['подготовка'] == вход['подготовка']['путь']
        and параметры['квитанция'] == вход['квитанция']['путь']
        and параметры['назначение_sha256'] == хранение.хэш(основание),
        'Подготовка относится к другому дочернему назначению')
    ожидаемая_команда = {'задача': исполнитель.задача, 'исполнитель': вход['задача'],
        'экземпляр': хранение.хэш(поручение), 'происхождение': 'поручение-корня',
        'позиция': поручение['источник'], 'текст': поручение['текст']}
    хранение.требовать(подготовка['команды'] == [ожидаемая_команда]
        and (подготовка['модель'].get('модель'), подготовка['модель'].get('усилие')) ==
            (попытка['аргументы']['model'], попытка['аргументы']['thinking']),
        'Первичные команды или модель не соответствуют передаче')
    хранение.требовать(квитанция['схема'] == 'fum.квитанция-создания-коммита.1'
        and квитанция['подготовка_sha256'] == вход['подготовка']['sha256']
        and квитанция['состояние'] == 'проверен'
        and квитанция['процесс'] == {'код': 0, 'тайм_аут': False, 'исполнение_завершено': True, 'прерывание': None}
        and квитанция['готовность'].get('фиксировать_этап') is True,
        'Непроверенная или неуспешная квитанция не сохраняется как проверенный коммит')
    ожидаемое = квитанция['ожидание']
    хранение.поля(ожидаемое, {'ветка', 'исходный_коммит', 'родители', 'дерево', 'сообщение_sha256',
        'автор', 'коммиттер', 'явные_даты'})
    хранение.требовать(ожидаемое['ветка'] == ветка and ожидаемое['исходный_коммит'] == база
        and ожидаемое['родители'] == [база] and ожидаемое['сообщение_sha256'] == подготовка['сообщение_sha256']
        and ожидаемое['автор'][:2] == [подготовка['имя_автора'], подготовка['исходный_автор'][1]]
        and ожидаемое['коммиттер'][:2] == подготовка['исходный_коммиттер'][:2]
        and ожидаемое['явные_даты'] == подготовка['явные_даты'], 'Квитанция изменяет ожидаемый объект передачи')
    снимок = снимок_области.снимок(корень, вход['задача'], база, каталоги)
    голова = снимок['владелец']['HEAD']
    хранение.требовать(голова != база and снимок['владелец']['ref'] == ветка
        and голова == квитанция['наблюдённый_коммит']
        and квитанция['результат'] == коммит.проверить_объект(корень, ожидаемое, голова),
        'Текущий H не совпадает с единственным проверенным дочерним коммитом')
    хранение.требовать(not хранение.гит(корень, '-c', 'core.fsmonitor=false', 'status', '--porcelain=v1',
        '--untracked-files=all', '--ignore-submodules=none').strip(), 'После H появились незакоммиченные байты')
    журнал = каталоги[1]
    хранение.требовать(параметры['запрос'] == журнал + 'запрос.md'
        and параметры['история_модели'].startswith(журнал + 'материалы/')
        and type(параметры['разрешённые_цели']) is list
        and set(снимок['файлы']) <= set(параметры['разрешённые_цели']), 'Состав H расходится с собственной передачей')
    история = хранение.гит(корень, 'show', голова + ':' + параметры['история_модели'], сырые=True)
    хранение.требовать(коммит.хэш(история) == подготовка['история_sha256'], 'История модели H расходится с подготовкой')
    хранение.требовать(_свидетельство(вход['подготовка']) == подготовка
        and _свидетельство(вход['квитанция']) == квитанция
        and остановка_ребёнка.снимок(вход['источник']) == записи
        and привязка.проверить(
            исполнитель, запись, 'события', попытка, наблюдение, вход['источник'], каталоги, ветка
        ) == (основание, поручение)
        and снимок_области.снимок(корень, вход['задача'], база, каталоги) == снимок,
        'Остановленный H изменился при проверке')
    return {'вид': 'остановлен-с-коммитом', 'задача': вход['задача'], 'корень': str(корень), 'C': база,
        'H': голова, 'ref': ветка, 'ход': ход, 'источник': вход['источник'],
        'наблюдение_sha256': хранение.хэш(наблюдение), 'подготовка': вход['подготовка'],
        'квитанция': вход['квитанция'], 'снимок_sha256': хранение.хэш(снимок), 'интегрирован': False}

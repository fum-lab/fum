"""Конечный план двух слоёв; неизвестное размещение сюда не подставляется."""
import copy
from pathlib import Path
import sys
import unicodedata

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "fum-reyestr-planirovaniya/scripts"))
import приём_направления as хранение
from паспорт_конвейера import сформировать_ref_ветки
import поколение_запуска


def проверить_план(план):
    новый = type(план) is dict and план.get('схема') == 'fum.план-запуска-двух-слоёв.2'
    хранение.поля(план, {"схема", "конвейер", "шаг", "слои"} | ({'предыдущий'} if новый else set()))
    хранение.требовать(план["схема"] in {"fum.план-запуска-двух-слоёв.1", "fum.план-запуска-двух-слоёв.2"}
                       and план["шаг"] == "FUM-STEP-0233" and хранение.текст(план["конвейер"]), "Неизвестный конечный план")
    суффикс = '--g-' + поколение_запуска.ссылка(план['предыдущий'])['терминал_sha256'] if новый else ''
    слои = план["слои"]
    хранение.требовать(type(слои) is list and len(слои) == 2, "Первый срез требует ровно два слоя")
    имена, каталоги, ветки = set(), [], set()
    for слой in слои:
        хранение.поля(слой, {"слой", "каталог", "роль", "ветка", "зависит_от", "поручение"})
        хранение.требовать(хранение.текст(слой["слой"]) and слой["слой"] not in имена
                           and хранение.текст(слой["роль"]), "Повторный слой либо пустая роль")
        имена.add(слой["слой"])
        каталог = слой["каталог"]
        хранение.требовать(type(каталог) is str and каталог.endswith("/") and каталог,
                           "Нужен непустой относительный каталог слоя")
        ожидаемая = сформировать_ref_ветки(каталог, "codex") + суффикс
        хранение.требовать(слой["ветка"] == ожидаемая and ожидаемая not in ветки,
                           "Ветка слоя не выведена из каталога либо повторяется")
        ветки.add(ожидаемая)
        сравнимый = unicodedata.normalize("NFC", каталог).casefold()
        хранение.требовать(not any(сравнимый.startswith(иной) or иной.startswith(сравнимый) for иной in каталоги),
                           "Каталоги двух писателей пересекаются")
        каталоги.append(сравнимый)
        хранение.путь_результата(слой["поручение"])
        зависимости = слой["зависит_от"]
        хранение.требовать(type(зависимости) is list and all(хранение.текст(x) for x in зависимости)
                           and len(set(зависимости)) == len(зависимости), "Неверные зависимости слоя")
    по_имени = {слой["слой"]: слой for слой in слои}
    for имя in имена:
        def посетить(текущий, путь):
            хранение.требовать(текущий in имена and текущий not in путь, "Неизвестная зависимость либо цикл слоёв")
            for родитель in по_имени[текущий]["зависит_от"]:
                посетить(родитель, путь | {текущий})
        посетить(имя, set())
    return copy.deepcopy(план)

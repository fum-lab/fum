"""Сопоставление остановленного назначенного писателя с приватным пакетом."""
from pathlib import Path

import приём_направления as хранение
import постановка_задачи as постановка
import остановка_ребёнка
import пакет_незавершённого
import хранилище_незавершённого


def проверить(исполнитель, вход, наблюдение, попытка, база, каталоги, ветка, ожидание):
    хранение.поля(вход, {'попытка', 'задача', 'корень', 'источник', 'пакет'})
    хранение.поля(вход['пакет'], {'путь', 'sha256'})
    хранение.требовать(хранение.абсолютный_корень(вход['корень'])
                       and вход['корень'] == наблюдение['корень']
                       and вход['задача'] == наблюдение['задача'] != исполнитель.задача
                       and вход['попытка'] == попытка['попытка'], 'Чужой сохранённый писатель')
    корень = Path(вход['корень'])
    хранение.требовать(корень.resolve() == корень and корень != исполнитель.корень, 'Нужен отдельный физический корень')
    общий = хранение.гит(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').strip()
    хранение.требовать(Path(общий) == исполнитель.хранилище.общий, 'Чужая Git-база ребёнка')
    записи = остановка_ребёнка.снимок(вход['источник'])
    ход = остановка_ребёнка.подтвердить_ход(записи, вход['задача'], ожидание)
    def первичное():
        return {**постановка.прочитать_подтверждение(корень, вход['задача'], база, вход['источник']['путь']),
                'поручение': постановка.проверить_нативное_поручение(вход['источник']['путь'], исполнитель.задача,
                    попытка['аргументы']['prompt'], кодирование='xml-v1')}
    хранение.требовать(первичное() == наблюдение and наблюдение['схема'] == 'fum.начальная-база-задачи.2',
                       'Изменилось раннее подтверждение писателя')
    описание, данные = хранилище_незавершённого.прочитать(вход['пакет']['путь'], вход['пакет']['sha256'])
    хранение.требовать(описание['база'] == база and описание['каталоги'] == каталоги
                       and описание['снимок']['владелец'] == {'задача': вход['задача'], 'путь': str(корень), 'ref': ветка, 'HEAD': база},
                       'Пакет относится к другому назначению')
    хранение.требовать(пакет_незавершённого.собрать(корень, вход['задача'], база, каталоги) == (описание, данные),
                       'Живые байты или индекс расходятся с сохранённым пакетом')
    хранение.требовать(первичное() == наблюдение and остановка_ребёнка.снимок(вход['источник']) == записи,
                       'Первичный источник ребёнка сдвинулся при проверке')
    return {'вид': 'остановлен-с-сохранением', 'задача': вход['задача'], 'корень': str(корень),
            'C': база, 'ref': ветка, 'ход': ход, 'источник': вход['источник'],
            'наблюдение_sha256': хранение.хэш(наблюдение), 'пакет': вход['пакет'],
            'снимок_sha256': хранение.хэш(описание['снимок']), 'разрешение_восстановления': False}

"""Порядок по первичному журналу и интервалам часов runtime одного координатора."""
import приём_направления as хранение


def проверить(нативный, номер, дети):
    хранение.требовать(нативный['схема'] == 'fum.наблюдённые-вызовы-запуска.2'
                       and нативный['источник']['начало'] == нативный['начальная_граница'],
                       'Нужна полная история с интервалами runtime')
    ожидания = нативный['ожидания']
    хранение.требовать(ожидания and ожидания[-1]['id'] == номер, 'Нужно последнее ожидание после воздействий')
    ожидание = ожидания[-1]
    цели = ожидание['аргументы']['targets']
    хранение.требовать(set(дети) <= {ц.get('threadId') for ц in цели}, 'Последнее ожидание не охватывает обоих детей')
    for воздействие in [*нативный['вызовы'], *нативный['возобновления']]:
        хранение.требовать(воздействие['инструмент'] in {'create_thread', 'send_message_to_thread'},
                           'Перенос задачи не поддержан этим переходом')
        хранение.требовать(воздействие['источник']['конец'] <= ожидание['источник']['начало']
                           and воздействие['интервал']['конец_мс'] < ожидание['интервал']['начало_мс'],
                           'Ожидание началось до завершения воздействия либо перекрывает его')
    return ожидание

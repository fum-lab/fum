"""Потоковая проверка физических архивов; кеш живёт только в одном приёмочном плане."""
import copy
import hashlib
import os
from pathlib import Path
import stat
import unicodedata

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import нативные_вызовы as нативные
from приватные_файлы_отказа import СнимокФайлов, _абсолютный, _метка

хранение = нативные.хранение
РАЗМЕР_БЛОКА = 4 * 1024 * 1024


def _обычный(путь, размер, *, приватный=False):
    хранение.безопасный_путь(путь)
    имя = unicodedata.normalize('NFC', путь.name)
    хранение.требовать(any(unicodedata.normalize('NFC', запись.name) == имя
        for запись in путь.parent.iterdir()), 'Регистр конечного имени архива не совпал')
    метаданные = путь.lstat()
    хранение.требовать(stat.S_ISREG(метаданные.st_mode) and метаданные.st_nlink == 1
        and метаданные.st_uid == os.getuid() and метаданные.st_size == размер
        and (not приватный or метаданные.st_mode & 0o077 == 0),
        'Нужен неизменяемый обычный архив правильного размера и владельца')
    return _метка(метаданные)


def остановка(описание, сырые):
    хранение.поля(описание, {'путь', 'граница', 'sha256'})
    хранение.требовать(type(описание['граница']) is int
        and 0 < описание['граница'] < len(сырые)
        and хранение.шестнадцатеричный(описание['sha256']), 'Неверная граница архива остановки')
    путь = _абсолютный(описание['путь'])
    файлы = СнимокФайлов()
    сохранённые = файлы.прочитать('остановка', путь, путь.parent, json=False,
        предел=нативные.ПРЕДЕЛ_СТРОКИ)
    хранение.требовать(len(сохранённые) == описание['граница']
        and сохранённые.endswith(b'\n') and сохранённые == сырые[:описание['граница']]
        and hashlib.sha256(сохранённые).hexdigest() == описание['sha256'],
        'Архив остановки не совпал с независимо прочитанным живым префиксом')
    return файлы.сверить()['остановка']


class АрхивыПриёма:
    def __init__(сам, полный):
        хранение.поля(полный, {'путь', 'начало', 'начало_sha256', 'граница', 'sha256'})
        хранение.требовать(type(полный['граница']) is int and полный['граница'] > 0,
            'Нужна точная граница полного ROOT')
        сам.полный = copy.deepcopy(полный)
        сам.путь = _абсолютный(полный['путь'])
        сам.метка_корня = _обычный(сам.путь, полный['граница'])
        сам.кеш = {}
        сам.разборы = сам.попадания = 0

    def _сравнить(сам, описание, файлы, прежняя_метка=None):
        путь = _абсолютный(описание['путь'])
        файлы._каталоги(путь, путь.parent)
        метка = _обычный(путь, описание['граница'], приватный=True)
        хранение.требовать(прежняя_метка is None or метка == прежняя_метка,
            'Архив изменился после первого чтения')
        хранение.требовать(_обычный(сам.путь, сам.полный['граница']) == сам.метка_корня,
            'Полный ROOT изменился после начала плана')
        полный, начало = hashlib.sha256(), hashlib.sha256()
        флаги = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK
        with os.fdopen(os.open(путь, флаги), 'rb') as архив, \
                os.fdopen(os.open(сам.путь, флаги), 'rb') as источник:
            хранение.требовать(_метка(os.fstat(архив.fileno())) == метка
                and _метка(os.fstat(источник.fileno())) == сам.метка_корня,
                'Подменён открытый архив или ROOT')
            позиция = 0
            while позиция < описание['граница']:
                блок = архив.read(min(РАЗМЕР_БЛОКА, описание['граница'] - позиция))
                хранение.требовать(блок and блок == источник.read(len(блок)),
                    'Физический архив не совпал с префиксом полного ROOT')
                полный.update(блок)
                if позиция < описание['начало']:
                    начало.update(блок[:описание['начало'] - позиция])
                позиция += len(блок)
            хранение.требовать(блок.endswith(b'\n') and not архив.read(1)
                and полный.hexdigest() == описание['sha256']
                and начало.hexdigest() == описание['начало_sha256'],
                'Подменён хэш или граница физического ROOT-архива')
            хранение.требовать(_метка(os.fstat(архив.fileno())) == метка
                and _метка(os.fstat(источник.fileno())) == сам.метка_корня,
                'Архив или ROOT сдвинулся во время потокового чтения')
        хранение.требовать(_обычный(путь, описание['граница'], приватный=True) == метка
            and _обычный(сам.путь, сам.полный['граница']) == сам.метка_корня,
            'Подменён архив или ROOT после чтения')
        файлы._каталоги(путь, путь.parent)
        return метка

    def прочитать(сам, описание, задача, дети):
        хранение.поля(описание, {'путь', 'начало', 'начало_sha256', 'граница', 'sha256'})
        хранение.требовать(type(описание['граница']) is int and type(описание['начало']) is int
            and 0 < описание['начало'] <= описание['граница'] < сам.полный['граница']
            and описание['начало'] == сам.полный['начало']
            and описание['начало_sha256'] == сам.полный['начало_sha256']
            and хранение.шестнадцатеричный(описание['sha256']),
            'Конверт из будущего или неполного ROOT')
        ключ = хранение.хэш({'архив': описание, 'полный': сам.полный, 'задача': задача,
            'дети': list(дети), 'интервалы': True, 'читать_создания': False})
        if ключ in сам.кеш:
            запись = сам.кеш[ключ]
            путь = _абсолютный(описание['путь'])
            запись['файлы']._каталоги(путь, путь.parent)
            хранение.требовать(_обычный(путь, описание['граница'], приватный=True) == запись['метка']
                and _обычный(сам.путь, сам.полный['граница']) == сам.метка_корня,
                'Кеш не разрешает подмену архива или ROOT')
            сам.попадания += 1
            return copy.deepcopy(запись['нативный'])
        файлы = СнимокФайлов()
        метка = сам._сравнить(описание, файлы)
        нативный = нативные.прочитать(описание, задача, ожидания=дети,
            интервалы=True, читать_создания=False)
        хранение.требовать(_обычный(_абсолютный(описание['путь']), описание['граница'],
            приватный=True) == метка, 'Архив изменился после независимого разбора')
        сам.кеш[ключ] = {'описание': copy.deepcopy(описание), 'файлы': файлы,
            'метка': метка, 'нативный': copy.deepcopy(нативный)}
        сам.разборы += 1
        return нативный

    def сверить(сам):
        for запись in сам.кеш.values():
            сам._сравнить(запись['описание'], запись['файлы'], запись['метка'])
        хранение.требовать(_обычный(сам.путь, сам.полный['граница']) == сам.метка_корня,
            'Полный ROOT сдвинулся перед возвратом плана')

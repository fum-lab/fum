"""Одна атомарная передача привязки и закрытой цепочки, без запуска задач."""
import copy
import hashlib
from pathlib import Path
import time

import приём_направления as хранение
import вход_направления as вход
import исполнитель_приёма as приём
import поколение_запуска
import терминал_запуска

СХЕМА = 'fum.переход-координатора.1'
СХЕМА_ПРИВЯЗКИ = 'fum.перенос-привязки-писателя.1'
ХЭШ_КОДА = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def подписать(запись):
    return {**запись, 'sha256': хранение.хэш(запись)}


def проверить_наблюдения(исполнитель, пакет):
    """Повторяется под замком; чужой checkout используется только для чтения."""
    получатель = исполнитель.хранилище._наблюдать_владельца()
    хранение.требовать(получатель == пакет['получатель'], 'Изменился получатель перехода')
    прежний = пакет['прежний_координатор']
    источник = хранение.Хранилище(прежний['путь'], исполнитель.задача)
    хранение.требовать(источник.общий == исполнитель.хранилище.общий
                       and источник._наблюдать_владельца() == прежний, 'Изменился прежний координатор или Git-база')
    отсутствующий = Path(пакет['прежнее_размещение']['путь'])
    хранение.безопасный_путь(отсутствующий, каталог=True)
    деревья = хранение.гит(исполнитель.корень, 'worktree', 'list', '--porcelain', '-z').split('\0')
    хранение.требовать(not отсутствующий.exists() and 'worktree ' + str(отсутствующий) not in деревья,
                       'Прежнее размещение ещё существует или зарегистрировано')
    хранение.гит(исполнитель.корень, 'merge-base', '--is-ancestor', прежний['HEAD'], получатель['HEAD'])
    исполнитель._инструменты(получатель['HEAD'])
    хранение.требовать(hashlib.sha256(Path(__file__).read_bytes()).hexdigest() == ХЭШ_КОДА, 'Код перехода изменён после загрузки')


def проверить_вход(исполнитель, пакет):
    хранение.поля(пакет, {'схема', 'задача', 'предыдущий', 'прежний_координатор', 'прежнее_размещение',
                        'получатель', 'источник', 'решение', 'свидетельство_координатора'})
    хранение.требовать(пакет['схема'] == 'fum.вход-перехода-координатора.1'
                       and пакет['задача'] == исполнитель.задача, 'Чужой вход перехода')
    поколение_запуска.ссылка(пакет['предыдущий'])
    for имя in ('прежний_координатор', 'получатель', 'прежнее_размещение'):
        назначение = пакет[имя]
        хранение.поля(назначение, {'задача', 'путь', 'ref'} | ({'HEAD'} if имя != 'прежнее_размещение' else set()))
        хранение.требовать(назначение['задача'] == исполнитель.задача and хранение.абсолютный_корень(назначение['путь'])
                           and хранение.ветка_писателя(назначение['ref']), 'Неверная идентичность назначения')
        if имя != 'прежнее_размещение':
            хранение.требовать(хранение.шестнадцатеричный(назначение['HEAD'], 40), 'Нужен точный HEAD назначения')
    хранение.требовать(пакет['прежнее_размещение']['ref'] == пакет['получатель']['ref']
                       and len({пакет[к]['путь'] for к in ('прежний_координатор', 'получатель', 'прежнее_размещение')}) == 3,
                       'Нужны разные размещения одного писателя и прежний координатор')
    хранение.требовать(пакет['свидетельство_координатора'] == {
        'задача': исполнитель.задача, 'единственный_координатор': True,
        'нет_незаписанных_или_выполняющихся_вызовов_этой_цепочки': True, 'прежняя_цепочка_не_возобновляется': True},
        'Нет явного кооперативного свидетельства передачи')
    решение = пакет['решение']
    хранение.требовать(type(решение) is dict and решение.get('действие') in {'новое', 'обновить'}
                       and решение.get('актуальность') in {'актуально', 'уточнено'}
                       and решение.get('объём') == 'реализация' and решение.get('задача') is None,
                       'Нет актуального решения о локальном переходе')
    проверенное = вход.проверить_решение(исполнитель.корень, пакет['источник'], исполнитель.задача, решение)
    проверить_наблюдения(исполнитель, пакет)
    return {'команда': проверенное['команда'], 'решение': приём.смысл_решения(решение)}


def закрытая_цепочка(исполнитель, состояние, пакет):
    цепочка, приёмы, попытки, виденные = [], {}, {}, set()
    предыдущий, логика = пакет['предыдущий'], None
    while предыдущий is not None:
        поколение_запуска.ссылка(предыдущий)
        ключ = предыдущий['запуск']
        хранение.требовать(ключ not in виденные, 'Цикл передаваемой цепочки')
        виденные.add(ключ)
        запись = исполнитель._проверить_запись(состояние, ключ, пакет['прежний_координатор']['путь'])
        план = запись['план']
        хранение.требовать(поколение_запуска.полное_поручение(запись['смысл']), 'Неполное прежнее поручение')
        текущая_логика = поколение_запуска.логический_план(план['описание'])
        хранение.требовать(логика is None or логика == текущая_логика, 'Изменён логический состав цепочки')
        логика = текущая_логика
        терминал = терминал_запуска.прочитать(состояние, ключ)
        записи_попыток = {слой: состояние['попытки'].get(к) for слой, к in план['попытки'].items()}
        хранение.требовать(терминал is not None and all(type(в) is dict for в in записи_попыток.values()), 'Предок не закрыт или потеряна попытка')
        хранение.требовать(терминал['sha256'] == предыдущий['терминал_sha256'] and терминал['план_sha256'] == план['sha256']
                           and терминал['история_sha256'] == хранение.хэш({'запись': запись, 'попытки': записи_попыток}),
                           'Изменён терминал или история цепочки')
        for координатор in (план['координатор'], терминал['координатор']):
            хранение.требовать(all(координатор[к] == пакет['прежний_координатор'][к] for к in ('задача', 'путь'))
                               and хранение.ветка_писателя(координатор['ref']), 'Чужой координатор цепочки')
            хранение.гит(исполнитель.корень, 'merge-base', '--is-ancestor', координатор['HEAD'], пакет['получатель']['HEAD'])
        цепочка.append({'запуск': ключ, 'план_sha256': план['sha256'], 'терминал_sha256': терминал['sha256'],
                       'история_sha256': терминал['история_sha256'], 'координатор_плана': план['координатор'],
                       'координатор_терминала': терминал['координатор']})
        приёмы.update({ключ: хранение.хэш(запись), терминал_запуска.ключ(ключ): хранение.хэш(терминал)})
        попытки.update({к: хранение.хэш(состояние['попытки'][к]) for к in план['попытки'].values()})
        предыдущий = запись['смысл'].get('предыдущий')
    return цепочка, {'приёмы': приёмы, 'попытки': попытки}


def собрать_план(привязка, координатор):
    return подписать({'схема': 'fum.план-перехода-координатора.1',
        'состояние_sha256': координатор['квитанция']['основание']['состояние_sha256'],
        'привязка': привязка, 'координатор': координатор})


def построить(исполнитель, пакет, состояние):
    основание = проверить_вход(исполнитель, пакет)
    ключ_привязки = хранение.хэш({'схема': СХЕМА_ПРИВЯЗКИ, 'прежний': пакет['прежнее_размещение']})
    ключ_координатора = хранение.хэш({'схема': СХЕМА, 'задача': пакет['задача'], 'предыдущий': пакет['предыдущий']})
    прежний = состояние['приёмы'].get(ключ_координатора)
    if прежний is not None:
        хранение.проверить_переходы(состояние)
        хранение.требовать(прежний['вход'] == пакет and прежний['основание']['решение'] == основание, 'Изменён неизменяемый переход')
        привязка = состояние['приёмы'][ключ_привязки]
        return собрать_план({'ключ': ключ_привязки, 'квитанция': привязка}, {'ключ': ключ_координатора, 'квитанция': прежний})
    хранение.требовать(ключ_привязки not in состояние['приёмы'], 'Привязка уже передана другим переходом')
    for имя in ('прежнее_размещение', 'прежний_координатор'):
        старый = пакет[имя]
        хранение.требовать(состояние['писатели'].get(старый['путь']) == {'задача': старый['задача'], 'ref': старый['ref']}, 'Потерян прежний владелец')
    получатель = пакет['получатель']
    хранение.требовать(получатель['путь'] not in состояние['писатели'], 'Получатель уже зарегистрирован')
    история = {раздел: {к: хранение.хэш(в) for к, в in состояние[раздел].items() if в['корень'] == пакет['прежнее_размещение']['путь']}
               for раздел in ('этапы', 'попытки')}
    хранение.требовать(история['этапы'] and not история['попытки'], 'Нужны только диагностические этапы отсутствующего размещения')
    for ключ in история['этапы']:
        этап = состояние['этапы'][ключ]
        хранение.требовать(этап['готов'] and этап['коммит'] is None, 'Архив не соответствует диагностическому состоянию')
        хранение.гит(исполнитель.корень, 'merge-base', '--is-ancestor', этап['база'], получатель['HEAD'])
    цепочка, закрытая = закрытая_цепочка(исполнитель, состояние, пакет)
    основание = {'решение': основание, 'состояние_sha256': хранение.хэш(состояние)}
    привязка = подписать({'схема': СХЕМА_ПРИВЯЗКИ, 'задача': пакет['задача'], 'прежний': copy.deepcopy(пакет['прежнее_размещение']),
                        'получатель': copy.deepcopy(получатель), 'история': история, 'основание_sha256': хранение.хэш(основание)})
    координатор = подписать({'схема': СХЕМА, 'вход': copy.deepcopy(пакет), 'основание': основание,
        'привязка': {'ключ': ключ_привязки, 'sha256': привязка['sha256']}, 'цепочка': цепочка, 'закрытая_история': закрытая})
    план = собрать_план({'ключ': ключ_привязки, 'квитанция': привязка}, {'ключ': ключ_координатора, 'квитанция': координатор})
    пробный = copy.deepcopy(состояние)
    установить_план(пробный, план)
    хранение.проверить_состояние(пробный, исполнитель.хранилище.общий)
    return план


def установить_план(состояние, план):
    перенос = план['привязка']['квитанция']
    состояние['писатели'].pop(перенос['прежний']['путь'])
    состояние['писатели'][перенос['получатель']['путь']] = {к: перенос['получатель'][к] for к in ('задача', 'ref')}
    for имя in ('привязка', 'координатор'):
        состояние['приёмы'][план[имя]['ключ']] = copy.deepcopy(план[имя]['квитанция'])
    состояние['схема'] = 'fum.приём-направлений.2'


def предпросмотр(исполнитель, пакет):
    начало = time.monotonic_ns()
    try:
        return построить(исполнитель, пакет, исполнитель.хранилище.прочитать())
    finally:
        исполнитель.хранилище.профиль.append({'стадия': 'предпросмотр перехода', 'длительность_наносекунды': time.monotonic_ns() - начало})


def перейти(исполнитель, пакет, ожидаемый_sha256):
    with исполнитель.хранилище.изменить() as состояние:
        план = построить(исполнитель, пакет, состояние)
        хранение.требовать(план['sha256'] == ожидаемый_sha256, 'Изменился предпросмотр перехода')
        if план['координатор']['ключ'] not in состояние['приёмы']:
            установить_план(состояние, план)
        проверить_наблюдения(исполнитель, пакет)
        исполнитель.хранилище.проверить_владельца_под_замком(состояние,
            ожидаемая_ветка=пакет['получатель']['ref'], ожидаемый_коммит=пакет['получатель']['HEAD'])
        return план

"""Чистый план новой пары: подтверждённое поручение и конечные служебные пути."""
import hashlib
from pathlib import Path
import sys

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import эпизод_приёма as эпизод
import приём_интеграции

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-struktura-papok-zaprosov/scripts'))
import request_folder_layout as каркас

хранение = эпизод.хранение


def будущие_пути(основание):
    журнал = основание['журнал']
    return [журнал + имя for имя in ('запрос.md', 'отчёт.md', 'материалы/история-модели.json',
        'материалы/запуски-проверок/1_' + основание['проверка'] + '.json')]


def подготовить(основание):
    эпизод.проверить_основание(основание)
    блок = основание['поручение']; нативный = основание['нативный_приём']
    текст = нативный.get('текст')
    хранение.требовать(нативный.get('схема') == 'fum.нативный-приём.1'
        and нативный.get('корневая_задача') == блок['корневая_задача']
        and нативный.get('исполнитель') == блок['исполнитель']
        and текст == приём_интеграции.сформировать(блок), 'Нет точного полученного поручения')
    журнал = основание['журнал']; основа = журнал.removeprefix('Журнал/').removesuffix('/')
    метка = основа.split('_MSK_', 1)[1]
    файлы, сведения = каркас.подготовить_собственную_пару(Path(блок['корень']), основа,
        метка, каркас._заголовок_из_метки(метка), блок['корневая_задача'], [текст])
    хранение.требовать(not сведения['idempotent'] and len(файлы) == 2,
        'План должен создать новую пару, существующая не принимается')
    записи = [{'путь': ф.path.as_posix(), 'режим': ф.mode, 'текст': ф.data.decode('utf-8'),
        'sha256': hashlib.sha256(ф.data).hexdigest(),
        'временный': журнал + '.подготовка-' + основание['эпизод'] + '-' + str(н)}
        for н, ф in enumerate(файлы, 1)]
    результат = {'схема': 'fum.план-журнала-приёма.1', 'основание_sha256': основание['sha256'],
        'эпизод': основание['эпизод'], 'журнал': журнал, 'изначально_отсутствовал': True,
        'файлы': записи, 'будущие_пути': будущие_пути(основание)}
    проверить(результат, основание)
    return результат


def проверить(план, основание):
    хранение.поля(план, {'схема', 'основание_sha256', 'эпизод', 'журнал',
        'изначально_отсутствовал', 'файлы', 'будущие_пути'})
    хранение.требовать(план['схема'] == 'fum.план-журнала-приёма.1'
        and план['основание_sha256'] == основание['sha256'] and план['эпизод'] == основание['эпизод']
        and план['журнал'] == основание['журнал'] and план['изначально_отсутствовал'] is True
        and план['будущие_пути'] == будущие_пути(основание), 'План другого основания или Журнала')
    хранение.требовать(type(план['файлы']) is list and len(план['файлы']) == 2,
        'Нужна точная пара файлов')
    for номер, (запись, путь) in enumerate(zip(план['файлы'], будущие_пути(основание)[:2]), 1):
        хранение.поля(запись, {'путь', 'режим', 'текст', 'sha256', 'временный'})
        хранение.требовать(запись['путь'] == путь
            and запись['временный'] == основание['журнал'] + '.подготовка-' + основание['эпизод'] + '-' + str(номер)
            and type(запись['режим']) is int
            and запись['режим'] == 0o644 and type(запись['текст']) is str
            and hashlib.sha256(запись['текст'].encode('utf-8')).hexdigest() == запись['sha256'],
            'Изменены байты, режим или адрес первоначальной пары')

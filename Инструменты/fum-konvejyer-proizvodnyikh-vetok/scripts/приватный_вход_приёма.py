"""Связать обнаруженный конверт со своим native и прежним конечным приёмом."""
import hashlib
import os
from pathlib import Path

import конверт_приёма as конверт
import снимок_нативного_источника as снимок
import приём_получателя
import вход_приёма
import нативное_поручение_приёма
import полный_поток_передачи

приём = приём_получателя.приём_интеграции
эпизод = приём_получателя.эпизод
коммит = приём_получателя.коммит
хранение = снимок.хранение
файлы = снимок.файлы
КОД = {Path(м.__file__).resolve(): hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
    for м in (конверт, снимок, файлы, снимок.история_модели, снимок.сообщения_задачи,
        нативное_поручение_приёма, полный_поток_передачи)}
КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def _свой(текст):
    блок = конверт.разобрать_текст(текст)
    хранение.требовать(блок['исполнитель'] == os.environ.get('CODEX_THREAD_ID')
        and блок['корень'] == str(Path.cwd().resolve()), 'Нужны собственные нативная задача и физический корень')
    приём.проверить_код(Path(блок['корень']), блок['база'], дополнительный_код=КОД)
    return блок, конверт.адрес(текст, получатель=True)


def прочитать(текст, *, живой=True):
    блок, каталог = _свой(текст)
    файлы._место(каталог); файлы._приватный(каталог, каталог=True)
    пакет = хранение.разобрать(файлы._читать(каталог / 'конверт.json'))
    конверт.проверить(пакет, текст)
    описание = хранение.разобрать(файлы._читать(каталог / 'пакет.json'))
    данные = хранение.разобрать(файлы._читать(каталог / 'вход.json'))
    исходник = снимок.прочитать(каталог / 'нативный', блок['исполнитель'], живой=False)
    хранение.требовать(описание == {'схема': 'fum.приватный-вход-приёма.1',
        'конверт_sha256': хранение.хэш(пакет), 'вход_sha256': хранение.хэш(данные),
        'снимок_sha256': хранение.хэш(исходник)}, 'Подменён пакет входа приёма')
    ожидаемый = {'схема': 'fum.вход-дочернего-приёма.1',
        **{к: пакет[к] for к in ('текст', 'план', 'свидетельство', 'коммит')},
        'реестр': str(каталог / 'владельцы.json'), 'источник': str(каталог / 'нативный/источник.jsonl')}
    хранение.требовать(данные == ожидаемый
        and файлы._читать(каталог / 'владельцы.json') == хранение.байты(пакет['владельцы'])
        and файлы._читать(каталог / 'поручение.txt') == текст.encode('utf-8'),
        'Изменены вычисленные входы приёма')
    проверить_исходник(блок, данные['источник'], данные['свидетельство'], текст)
    if живой:
        снимок.наблюдать(каталог / 'нативный', блок['исполнитель'], каталог / 'наблюдение.json')
    return данные


def проверить_исходник(блок, источник, свидетельство, текст):
    получено = конверт.нативный_приём.прочитать_вход(источник, свидетельство['остановка'],
        блок['корневая_задача'], блок['исполнитель'], блок['корень'], текст)
    сырые, _ = снимок._сырой(источник)
    хранение.требовать(hashlib.sha256(сырые[:получено['конец']]).hexdigest() == получено['префикс_sha256'],
        'Изменён принятый префикс до проверки полного хвоста')
    полный_поток_передачи.проверить(сырые, получено['конец'], транспорт='send_message_to_thread')


def _параметры(данные):
    блок = конверт.разобрать_текст(данные['текст'])
    прежнее = эпизод.найти(блок['исполнитель'], блок['назначение_sha256'])
    хранение.требовать(прежнее is not None, 'Эпизод приёма ещё не установлен')
    параметры = вход_приёма.параметры(данные, прежнее['основание'])
    путь = эпизод.путь_эпизода(прежнее['основание']).with_suffix('.вход-коммита.json')
    хранение.требовать(эпизод.прочитать_файл(путь) == параметры, 'Изменён сохранённый вход коммита')
    return параметры


def _готовый_R(данные):
    блок = конверт.разобрать_текст(данные['текст'])
    прежнее = эпизод.найти(блок['исполнитель'], блок['назначение_sha256'])
    if прежнее is None:
        return False
    параметры = _параметры(данные)
    return os.path.lexists(параметры['квитанция'])


def подготовить_вход(текст, источник):
    блок, каталог = _свой(текст)
    источник = Path(источник)
    if каталог.exists():
        данные = прочитать(текст, живой=False)
        описание = снимок.прочитать(каталог / 'нативный', блок['исполнитель'], живой=False)
        хранение.требовать(описание['источник'] == str(источник), 'Источник существующего приёма изменён')
        if not _готовый_R(данные):
            прочитать(текст)
    else:
        пакет = конверт.ожидать(текст, 0)
        if пакет is None:
            return {'состояние': 'ожидается-конверт', 'разрешение_записи': False}
        проверить_исходник(блок, источник, пакет['свидетельство'], текст)
        # До локального пакета проверяется полное живое происхождение и допуск C/H/S.
        приём.прочитать(Path(блок['корень']), блок['исполнитель'], источник,
            пакет['план'], пакет['свидетельство'], текст)
        хранение.создать_каталоги(каталог.parent, Path(каталог.anchor), права=0o700)
        файлы._место(каталог); каталог.mkdir(mode=0o700)
        описание = снимок.создать(источник, блок['исполнитель'], каталог / 'нативный')
        файлы._записать(каталог / 'конверт.json', хранение.байты(пакет))
        файлы._записать(каталог / 'владельцы.json', хранение.байты(пакет['владельцы']))
        файлы._записать(каталог / 'поручение.txt', текст.encode('utf-8'))
        данные = {'схема': 'fum.вход-дочернего-приёма.1',
            **{к: пакет[к] for к in ('текст', 'план', 'свидетельство', 'коммит')},
            'источник': str(каталог / 'нативный/источник.jsonl'), 'реестр': str(каталог / 'владельцы.json')}
        файлы._записать(каталог / 'вход.json', хранение.байты(данные))
        снимок.наблюдать(каталог / 'нативный', блок['исполнитель'], каталог / 'наблюдение.json', первое=True)
        файлы._записать(каталог / 'пакет.json', хранение.байты({
            'схема': 'fum.приватный-вход-приёма.1', 'конверт_sha256': хранение.хэш(пакет),
            'вход_sha256': хранение.хэш(данные), 'снимок_sha256': хранение.хэш(описание)}))
        хранение.синхронизировать_каталог(каталог)
        хранение.синхронизировать_каталог(каталог.parent)
        прочитать(текст)
    результат = приём_получателя.подготовить(каталог / 'вход.json')
    return {**результат, 'поручение': str(каталог / 'поручение.txt'),
        'наблюдение_после': наблюдение_после(текст)}


def наблюдение_после(текст):
    try:
        прочитать(текст)
        return {'состояние': 'проверено', 'новые_действия_разрешены': True}
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as ошибка:
        return {'состояние': 'нужен разбор', 'причина': str(ошибка), 'новые_действия_разрешены': False}


def выполнить_фазу(текст, фаза, предел=600):
    хранение.требовать(фаза in {'подготовить', 'готово', 'создать'}, 'Неизвестная фаза приёма')
    данные = прочитать(текст, живой=False)
    параметры = _параметры(данные)
    подготовка = Path(параметры['подготовка'])
    проверки = [параметры['приём']['основание']['проверка']]
    if фаза != 'подготовить':
        сохранённая = хранение.разобрать(коммит.прочитать(подготовка, приватный=True))
        хранение.требовать(сохранённая.get('параметры') == параметры, 'Подготовка принадлежит другому приёму')
    восстановление = фаза == 'создать' and os.path.lexists(параметры['квитанция'])
    if not восстановление:
        прочитать(текст)
    if фаза == 'подготовить':
        результат = коммит.подготовить(параметры)
    elif фаза == 'готово':
        результат = коммит.объявить_готовность(подготовка, проверки, предел, {})
    else:
        результат = коммит.создать(подготовка, проверки)
    return {'схема': 'fum.фаза-приватного-приёма.1', 'фаза': фаза, 'результат': результат,
        'восстановление': восстановление, 'наблюдение_после': наблюдение_после(текст)}

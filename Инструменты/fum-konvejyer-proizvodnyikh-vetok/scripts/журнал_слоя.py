"""План собственной пары и отдельная установка подтверждённого поручения."""
import hashlib
from pathlib import Path
import sys

import дочернее_назначение
import приём_направления as хранение

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "fum-struktura-papok-zaprosov/scripts"))
import request_folder_layout as каркас

КОД = {Path(имя).resolve(): hashlib.sha256(Path(имя).read_bytes()).hexdigest()
       for имя in (__file__, каркас.__file__)}


def подготовить(корень, задача, источник, сообщения):
    """Происхождение переданных сообщений проверяет отдельный допуск коммита."""
    назначение = дочернее_назначение.прочитать(корень, задача, источник)
    журнал = назначение["каталоги"][1]
    основа = журнал.removeprefix("Журнал/").removesuffix("/")
    метка = основа.split("_MSK_", 1)[1]
    заголовок = каркас._заголовок_из_метки(метка)
    файлы, сведения = каркас.подготовить_собственную_пару(
        Path(корень), основа, метка, заголовок, назначение["корневая_задача"], сообщения,
        происхождение_времени=("канонический способ подготовки времени координатором; "
            f"префикс {основа.split('_MSK_', 1)[0]}_MSK закреплён в C={назначение['база']}, "
            f"в {назначение['назначение']['назначение']}. Ребёнок использует его без получения нового времени. "
            "Это время подготовки назначения; время запуска ребёнка не утверждается."))
    ожидаемые = {журнал + имя for имя in ("запрос.md", "отчёт.md")}
    хранение.требовать((not файлы and сведения["idempotent"])
                       or len(файлы) == 2 and {э.path.as_posix() for э in файлы} == ожидаемые,
                       "План пары вышел за назначенный Журнал")
    хранение.требовать(дочернее_назначение.прочитать(корень, задача, источник) == назначение,
                       "Назначение сдвинулось при подготовке пары")
    for путь, отпечаток in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == отпечаток, "Код плана Журнала изменён после загрузки")
    return файлы, {"схема": "fum.план-журнала-слоя.1", "назначение_sha256": назначение["sha256"],
                   "пара": сведения, "разрешение_установки": False, "происхождение_сообщений_проверено": False}


def установить(корень, задача, источник):
    """Сохранить точное агентское поручение; человеческий ввод не конструируется."""
    import нативное_назначение
    import запись_слоя
    первоначальное = нативное_назначение.прочитать(источник)
    файлы, сведения = подготовить(корень, задача, источник, [первоначальное['текст']])
    хранение.требовать(нативное_назначение.прочитать(источник) == первоначальное,
                       'Первоначальное поручение изменилось до установки')
    результат = запись_слоя.установить(корень, задача, источник, файлы, сведения['назначение_sha256'])
    return {**результат, 'повтор': сведения['пара']['idempotent'],
            'происхождение': 'первоначальное поручение корня'}

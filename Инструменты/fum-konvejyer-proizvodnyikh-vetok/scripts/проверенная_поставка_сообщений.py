def _пакет(вход, параметры, подготовка, сырые, идентичность):
    каталог = Path(вход['пакет_передачи']['путь']).parent
    хранение.требовать(Path(вход['пакет_передачи']['путь']).name == 'пакет.json'
        and параметры['подготовка'] == str(каталог / 'подготовка.json')
        and параметры['квитанция'] == str(каталог / 'квитанция.json')
        and параметры['источник_модели'] == str(каталог / 'нативный/источник.jsonl'),
        'Подготовка не относится к штатному приватному пакету')
    пакет = _свидетельство(вход['пакет_передачи'])
    хранение.поля(пакет, {'схема', 'задача', 'вход_sha256', 'снимок_sha256'})
    исходный_вход = хранение.разобрать(коммит.прочитать(каталог / 'вход.json', приватный=True))
    хранение.требовать(пакет['схема'] == 'fum.приватный-вход-передачи.1'
        and пакет['задача'] == вход['задача'] and исходный_вход == параметры
        and пакет['вход_sha256'] == хранение.хэш(параметры), 'Изменён штатный вход передачи S')
    описание = снимок.прочитать(каталог / 'нативный', вход['задача'], живой=False)
    frozen = снимок.файлы._читать(каталог / 'нативный/источник.jsonl')
    хранение.требовать(пакет['снимок_sha256'] == хранение.хэш(описание)
        and описание['источник'] == вход['источник']['путь']
        and описание['идентичность'] == идентичность and сырые.startswith(frozen),
        'Замороженный источник не является исходным префиксом полного Native S')
    история = снимок._модель(frozen, вход['задача'])
    хранение.требовать(подготовка['модель'] == история['последнее']
        and подготовка['наблюдений'] == история['число_наблюдений'], 'Модель подготовки расходится со снимком')
    return описание, история


def _местные(исполнитель, вход, запись, наблюдение, попытка, база, каталоги, ветка, ожидание,
        *, слой='сообщения', префикс=False):
    хранение.требовать(слой in {'события', 'сообщения'} and type(префикс) is bool,
        'Неизвестный вид первоначальной передачи')
    хранение.поля(вход, {'вид', 'попытка', 'задача', 'корень', 'источник', 'подготовка', 'квитанция',
        'пакет_передачи', 'публикация'})
    хранение.требовать(вход['вид'] == 'остановлен-с-коммитом'
        and вход['попытка'] == попытка['попытка'] and вход['задача'] == наблюдение['задача']
        and вход['корень'] == наблюдение['корень'] and вход['задача'] != исполнитель.задача,
        'Чужой остановленный писатель сообщений')
    корень = Path(вход['корень'])
    хранение.требовать(корень.is_absolute() and корень == корень.resolve() and корень != исполнитель.корень
        and Path(хранение.гит(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').strip())
            == исполнитель.хранилище.общий, 'Нужен отдельный ребёнок той же Git-базы')
    чтение = поток.прочитать_префикс if префикс else поток.прочитать
    сырые, идентичность, ход = чтение(вход['источник'], вход['задача'], str(корень), база,
        попытка['аргументы']['model'], попытка['аргументы']['thinking'], ожидание)
    основание, поручение = привязка.проверить(
        исполнитель, запись, слой, попытка, наблюдение, вход['источник'], каталоги, ветка)
    подготовка = _свидетельство(вход['подготовка']); квитанция = _свидетельство(вход['квитанция'])
    хранение.поля(подготовка, {'схема', 'параметры', 'имя_автора', 'готовность', 'команды', 'модель',
        'наблюдений', 'история_sha256', 'сообщение_sha256', 'исходный_автор', 'исходный_коммиттер', 'явные_даты'})
    хранение.поля(квитанция, {'схема', 'состояние', 'ожидание', 'подготовка_sha256', 'проверки',
        'допуск', 'готовность', 'индекс_sha256', 'подготовка_наносекунды', 'профиль', 'процесс',
        'наблюдённый_коммит', 'результат'})
    параметры = подготовка['параметры']
    хранение.поля(параметры, {'схема', 'корень', 'ветка', 'исходный_коммит', 'родители', 'задача',
        'имя_автора', 'запрос', 'источник_модели', 'кэш_модели', 'история_модели', 'источники', 'заголовок',
        'описание', 'сообщение', 'подготовка', 'квитанция', 'режим', 'разрешённые_цели', 'исполнитель', 'назначение_sha256'})
    хранение.требовать(подготовка['схема'] == 'fum.подготовленный-коммит.5'
        and параметры['схема'] == 'fum.создание-коммита.3' and параметры['режим'] == 'дочерняя-передача'
        and параметры['корень'] == str(корень) and параметры['ветка'] == ветка
        and параметры['задача'] == исполнитель.задача and параметры['исполнитель'] == вход['задача']
        and параметры['исходный_коммит'] == база and параметры['родители'] == [база]
        and параметры['источники'] == [] and параметры['подготовка'] == вход['подготовка']['путь']
        and параметры['квитанция'] == вход['квитанция']['путь']
        and параметры['назначение_sha256'] == хранение.хэш(основание), 'Чужое дочернее назначение подготовки S')
    команда = {'задача': исполнитель.задача, 'исполнитель': вход['задача'],
        'экземпляр': хранение.хэш(поручение), 'происхождение': 'поручение-корня',
        'позиция': поручение['источник'], 'текст': поручение['текст']}
    хранение.требовать(подготовка['команды'] == [команда]
        and (подготовка['модель'].get('модель'), подготовка['модель'].get('усилие')) ==
            (попытка['аргументы']['model'], попытка['аргументы']['thinking']), 'Чужие команда или модель передачи S')
    описание, модель = _пакет(вход, параметры, подготовка, сырые, идентичность)
    хранение.требовать(квитанция['схема'] == 'fum.квитанция-создания-коммита.1'
        and квитанция['подготовка_sha256'] == вход['подготовка']['sha256'] and квитанция['состояние'] == 'проверен'
        and квитанция['процесс'] == {'код': 0, 'тайм_аут': False, 'исполнение_завершено': True, 'прерывание': None}
        and квитанция['готовность'].get('фиксировать_этап') is True, 'Непроверенный коммит S')
    ожидаемое = квитанция['ожидание']
    хранение.поля(ожидаемое, {'ветка', 'исходный_коммит', 'родители', 'дерево', 'сообщение_sha256',
        'автор', 'коммиттер', 'явные_даты'})
    хранение.требовать(ожидаемое['ветка'] == ветка and ожидаемое['исходный_коммит'] == база
        and ожидаемое['родители'] == [база] and ожидаемое['сообщение_sha256'] == подготовка['сообщение_sha256']
        and ожидаемое['автор'][:2] == [подготовка['имя_автора'], подготовка['исходный_автор'][1]]
        and ожидаемое['коммиттер'][:2] == подготовка['исходный_коммиттер'][:2]
        and ожидаемое['явные_даты'] == подготовка['явные_даты'], 'Изменён ожидаемый объект S')
    состояние = снимок_области.снимок(корень, вход['задача'], база, каталоги)
    голова = состояние['владелец']['HEAD']
    хранение.требовать(голова != база and состояние['владелец']['ref'] == ветка
        and голова == квитанция['наблюдённый_коммит']
        and квитанция['результат'] == коммит.проверить_объект(корень, ожидаемое, голова),
        'Текущий S расходится с единственным проверенным коммитом')
    хранение.требовать(not хранение.гит(корень, '-c', 'core.fsmonitor=false', 'status', '--porcelain=v1',
        '--untracked-files=all', '--ignore-submodules=none').strip(), 'После S появились незакоммиченные байты')
    журнал = каталоги[1]
    хранение.требовать(параметры['запрос'] == журнал + 'запрос.md'
        and параметры['история_модели'].startswith(журнал + 'материалы/')
        and type(параметры['разрешённые_цели']) is list
        and set(состояние['файлы']) <= set(параметры['разрешённые_цели']), 'Состав S расходится с передачей')
    история = хранение.гит(корень, 'show', голова + ':' + параметры['история_модели'], сырые=True)
    хранение.требовать(коммит.хэш(история) == подготовка['история_sha256']
        and хранение.разобрать(история) == модель, 'История модели S расходится со снимком и подготовкой')
    хранение.требовать(_свидетельство(вход['подготовка']) == подготовка
        and _свидетельство(вход['квитанция']) == квитанция
        and _пакет(вход, параметры, подготовка, сырые, идентичность) == (описание, модель)
        and привязка.проверить(исполнитель, запись, слой, попытка, наблюдение,
            вход['источник'], каталоги, ветка) == (основание, поручение)
        and снимок_области.снимок(корень, вход['задача'], база, каталоги) == состояние,
        'S изменился при чтении свидетельств')
    итог = {'вид': 'остановлен-с-коммитом', 'задача': вход['задача'], 'корень': str(корень), 'C': база,
        'S': голова, 'ref': ветка, 'ход': ход, 'источник': вход['источник'],
        'наблюдение_sha256': хранение.хэш(наблюдение), 'подготовка': вход['подготовка'],
        'квитанция': вход['квитанция'], 'пакет_передачи': вход['пакет_передачи'],
        'снимок_sha256': хранение.хэш(состояние), 'модельный_снимок_sha256': хранение.хэш(описание),
        'интегрирован': False}
    if префикс: итог['назначение_sha256'] = параметры['назначение_sha256']
    return итог


def проверить_публикацию(корень, вход):
    хранение.поля(вход, {'коммит', 'ref', 'адрес_sha256'})
    адреса = хранение.гит(корень, 'remote', 'get-url', '--push', '--all', 'origin').splitlines()
    хранение.требовать(len(адреса) == 1 and хранение.хэш(адреса[0]) == вход['адрес_sha256']
        and хранение.гит(корень, 'remote', 'get-url', '--all', 'origin').splitlines() == адреса,
        'Неоднозначный или сменившийся origin S')
    строки = хранение.гит(корень, 'ls-remote', '--refs', адреса[0], вход['ref']).splitlines()
    хранение.требовать(строки == [вход['коммит'] + '\t' + вход['ref']], 'Удалённый OID не подтверждает публикацию S')
    хранение.требовать(хранение.гит(корень, 'remote', 'get-url', '--push', '--all', 'origin').splitlines() == адреса
        and хранение.гит(корень, 'remote', 'get-url', '--all', 'origin').splitlines() == адреса,
        'Origin изменился при подтверждении публикации')
    return dict(вход)


def проверить(*аргументы):
    return _проверить_публикуемую(*аргументы)


def проверить_префикс(*аргументы, слой):
    """Две штатные замороженные передачи; поздний приём проверяет терминал .9."""
    return _проверить_публикуемую(*аргументы, слой=слой, префикс=True)


def _проверить_публикуемую(*аргументы, **режим):
    до = _местные(*аргументы, **режим)
    вход = аргументы[1]
    хранение.поля(вход['публикация'], {'коммит', 'ref', 'адрес_sha256'})
    хранение.требовать(вход['публикация']['коммит'] == до['S']
        and вход['публикация']['ref'] == до['ref'], 'Публикуется иной объект S')
    публикация = проверить_публикацию(Path(до['корень']), вход['публикация'])
    хранение.требовать(_местные(*аргументы, **режим) == до, 'S изменился во время проверки публикации')
    return {**до, 'публикация': публикация}

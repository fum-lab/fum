"""Неизменяемая приватная копия пакета вне Git; восстановление не выполняется."""
import os
from pathlib import Path
import stat

import пакет_незавершённого as пакет

хранение = пакет.хранение


def _приватный(путь, каталог=False):
    хранение.безопасный_путь(путь, каталог=каталог)
    хранение.требовать(путь.exists(), 'Отсутствует часть приватного пакета')
    сведения = путь.stat()
    хранение.требовать(сведения.st_uid == os.getuid()
                       and stat.S_IMODE(сведения.st_mode) == (0o700 if каталог else 0o400),
                       'Неверный владелец или права приватного пакета')


def _место(цель):
    цель = Path(цель)
    хранение.требовать(хранение.абсолютный_корень(str(цель)), 'Нужен абсолютный путь пакета')
    хранение.безопасный_путь(цель, каталог=True)
    for предок in [цель, *цель.parents]:
        метка = предок / '.git'
        хранение.требовать(not метка.exists() and not метка.is_symlink(), 'Приватный пакет запрещён внутри Git')
        хранение.требовать(not ((предок / 'HEAD').exists() and (предок / 'objects').is_dir()
                                and (предок / 'refs').is_dir()), 'Приватный пакет запрещён внутри bare Git')
    _приватный(цель.parent, каталог=True)
    return цель


def _читать(путь):
    _приватный(путь)
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(дескриптор, 'rb') as поток:
        сведения = os.fstat(поток.fileno())
        хранение.требовать(stat.S_ISREG(сведения.st_mode) and сведения.st_nlink == 1
                           and сведения.st_uid == os.getuid() and stat.S_IMODE(сведения.st_mode) == 0o400,
                           'Изменились свойства объекта пакета')
        return поток.read()


def _записать(путь, байты):
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o400)
    with os.fdopen(дескриптор, 'wb') as поток:
        os.fchmod(поток.fileno(), 0o400)
        поток.write(байты)
        поток.flush()
        os.fsync(поток.fileno())


def прочитать(цель, ожидаемый):
    цель = _место(цель)
    _приватный(цель, каталог=True)
    хранение.требовать({п.name for п in цель.iterdir()} == {'описание.json', 'объекты'}, 'Неполный или лишний состав пакета')
    _приватный(цель / 'объекты', каталог=True)
    исходник = _читать(цель / 'описание.json')
    описание = хранение.разобрать(исходник)
    хранение.требовать(исходник == хранение.байты(описание), 'Неканоническое описание пакета')
    данные = {}
    for путь in (цель / 'объекты').iterdir():
        хранение.требовать(хранение.шестнадцатеричный(путь.name), 'Неизвестный объект пакета')
        данные[путь.name] = _читать(путь)
    хранение.требовать(пакет.проверить(описание, данные) == ожидаемый, 'Прочитан другой пакет')
    return описание, данные


def _повторить_синхронизацию(цель):
    for путь in [*(цель / 'объекты').iterdir(), цель / 'описание.json']:
        _приватный(путь)
        дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
        try:
            os.fsync(дескриптор)
        finally:
            os.close(дескриптор)
    for путь in [цель / 'объекты', цель, цель.parent]:
        хранение.синхронизировать_каталог(путь)


def сохранить(цель, описание, данные):
    ожидаемый = пакет.проверить(описание, данные)
    цель = _место(цель)
    if цель.exists():
        хранение.требовать(прочитать(цель, ожидаемый) == (описание, данные), 'Существующий пакет отличается')
        _повторить_синхронизацию(цель)
        хранение.требовать(прочитать(цель, ожидаемый) == (описание, данные), 'Пакет изменился при синхронизации')
        return ожидаемый
    цель.mkdir(mode=0o700)
    (цель / 'объекты').mkdir(mode=0o700)
    for хэш, байты in данные.items():
        _записать(цель / 'объекты' / хэш, байты)
    хранение.синхронизировать_каталог(цель / 'объекты')
    _записать(цель / 'описание.json', хранение.байты(описание))
    хранение.синхронизировать_каталог(цель)
    хранение.синхронизировать_каталог(цель.parent)
    хранение.требовать(прочитать(цель, ожидаемый) == (описание, данные), 'Сохранённый пакет отличается')
    return ожидаемый

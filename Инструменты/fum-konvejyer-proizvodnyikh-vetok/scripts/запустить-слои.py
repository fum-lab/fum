#!/usr/bin/env python3
"""Локальные стадии запуска; ни одна команда не вызывает Desktop сама."""
import argparse
import json
import os
from pathlib import Path

from запуск_слоёв import ИсполнительЗапускаСлоёв
import приём_направления as хранение


def выполнить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--корень-репозитория", required=True)
    парсер.add_argument("--задача", required=True)
    команды = парсер.add_subparsers(dest="команда", required=True)
    for имя in ("предпросмотр", "подготовить", "допустить", "завершение-предпросмотр", "завершить"):
        команда = команды.add_parser(имя)
        команда.add_argument("--вход", required=True)
        if имя in ("подготовить", "завершить"):
            команда.add_argument("--sha256", required=True)
        if имя == "допустить":
            команда.add_argument("--слой", required=True)
    for имя in ("сохранить", "наблюдать", "состояние", "область"):
        команда = команды.add_parser(имя)
        команда.add_argument("--запуск", required=True)
        if имя != "состояние":
            команда.add_argument("--слой", required=True)
        if имя == "сохранить":
            команда.add_argument("--попытка", required=True)
            команда.add_argument("--ответ", required=True)
        if имя == "наблюдать":
            команда.add_argument("--корень-ребёнка", required=True)
            команда.add_argument("--задача-ребёнка", required=True)
            команда.add_argument("--источник", required=True)
        if имя == "область":
            команда.add_argument("--назначение", required=True)
            команда.add_argument("--источник", required=True)
    аргументы = парсер.parse_args()
    хранение.требовать(os.environ.get("CODEX_THREAD_ID") == аргументы.задача, "Нативный UUID не совпадает с корневой задачей")
    исполнитель = ИсполнительЗапускаСлоёв(аргументы.корень_репозитория, аргументы.задача)
    def прочитать(имя):
        путь = Path(имя).absolute()
        хранение.безопасный_путь(путь)
        хранение.требовать(not any((родитель / ".git").exists() for родитель in путь.parents), "Приватный вход должен находиться вне Git")
        return хранение.разобрать(путь.read_bytes())
    имя = аргументы.команда
    if имя in ("завершение-предпросмотр", "завершить"):
        import завершение_запуска
        пакет = прочитать(аргументы.вход)
        if имя == "завершение-предпросмотр":
            return завершение_запуска.предпросмотр(исполнитель, пакет)
        return завершение_запуска.завершить(исполнитель, пакет, аргументы.sha256)
    if имя in ("предпросмотр", "подготовить", "допустить"):
        пакет = прочитать(аргументы.вход)
        if имя == "предпросмотр":
            return исполнитель.предпросмотр(пакет)
        if имя == "подготовить":
            return исполнитель.подготовить(пакет, аргументы.sha256)
        return исполнитель.допустить(пакет, аргументы.слой)
    if имя == "сохранить":
        return исполнитель.сохранить(аргументы.запуск, аргументы.слой, аргументы.попытка, прочитать(аргументы.ответ))
    if имя == "наблюдать":
        return исполнитель.наблюдать(аргументы.запуск, аргументы.слой, аргументы.корень_ребёнка, аргументы.задача_ребёнка, аргументы.источник)
    if имя == "область":
        return исполнитель.область(аргументы.запуск, аргументы.слой, аргументы.назначение, аргументы.источник)
    return исполнитель.состояние(аргументы.запуск)


if __name__ == "__main__":
    try:
        print(json.dumps(выполнить(), ensure_ascii=False, sort_keys=True))
    except (ValueError, OSError) as ошибка:
        print(json.dumps({"схема": "fum.отказ-запуска-слоёв.1", "ошибка": str(ошибка)}, ensure_ascii=False))
        raise SystemExit(2)

"""Ограниченное наблюдение первоначальных прав; прав и разрешения записи не выдаёт."""
import hashlib
import os
from pathlib import Path
from types import SimpleNamespace

import приём_направления as хранение
import постановка_задачи as постановка
import исполнитель_приёма as приём
import план_запуска_слоёв
import поручение_слоя
import нативное_назначение
import остановка_ребёнка
from отложенные_назначения import манифест_коммита

ПОЛИТИКА = {
    'approval_policy': 'never', 'approvals_reviewer': 'user',
    'sandbox_policy': {'type': 'danger-full-access'},
    'permission_profile': {'type': 'disabled'},
    'active_permission_profile': {'id': ':danger-full-access'},
}
КОД = {Path(м.__file__).resolve(): hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
       for м in (хранение, постановка, приём, план_запуска_слоёв, поручение_слоя, нативное_назначение, остановка_ребёнка)}
КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def прочитать(корень, задача, база, источник):
    корень = Path(корень).resolve()
    начало, контекст, граница = постановка.прочитать_начало_источника(источник)
    хранение.требовать(начало.get('id') == задача and начало.get('cwd') == str(корень)
        and контекст.get('cwd') == str(корень) and type(начало.get('git')) is dict
        and начало['git'].get('commit_hash') == база, 'Права относятся к другой задаче, базе или дереву')
    хранение.требовать((контекст.get('model'),контекст.get('effort')) == ('gpt-6-sol','ultra'),
        'Первоначальный профиль прав относится к другой модели')
    хранение.требовать(all(к in контекст and type(контекст[к]) is type(в) and контекст[к] == в
        for к,в in ПОЛИТИКА.items()) and 'file_system_sandbox_policy' not in контекст,
        'Неизвестная, неполная или противоречивая первоначальная политика прав')
    хранение.требовать(постановка.прочитать_начало_источника(источник) == (начало,контекст,граница),
        'Начальная политика сдвинулась при чтении')
    return {'схема':'fum.первоначальные-права-запуска.1','задача':задача,'корень':str(корень),
        'база':база,'профиль_модели':{'model':'gpt-6-sol','thinking':'ultra'},
        'политика':{к:контекст[к] for к in ПОЛИТИКА},'источник':граница,'разрешение_записи':False}


def проверить_код(корень, база):
    приём.проверить_инструменты(корень,база)
    for путь, хэш in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest()==хэш,
            'Код проверки прав изменён после загрузки')


def проверить_до_записи(корень, задача, источник):
    хранение.требовать(хранение.идентификатор_задачи(задача) and os.environ.get('CODEX_THREAD_ID')==задача,
        'Нативный UUID не совпал с собственным ребёнком')
    хранилище = хранение.Хранилище(корень,задача); корень = хранилище.корень
    поручение = нативное_назначение.прочитать(источник); блок = поручение['назначение']; база = блок['база']
    хранение.требовать(блок['схема']=='fum.первоначальное-назначение-слоя.3' and блок['корневая_задача']!=задача
        and хранение.шестнадцатеричный(база,40), 'Нужен исходный Sol/Ultra-профиль собственного назначения')
    проверить_код(корень,база)
    файлы=манифест_коммита(корень,база,блок['файлы'])
    хранение.требовать({блок['план'],блок['назначение']} <= set(файлы), 'Сокращён манифест назначения')
    план=план_запуска_слоёв.проверить_план(хранение.разобрать(файлы[блок['план']]))
    слои={с['слой']:с for с in план['слои']}
    хранение.требовать(блок['слой'] in слои and all(с['поручение'] in файлы for с in слои.values()),
        'Нет исходного поручения слоя')
    слой=слои[блок['слой']]
    ожидаемый=поручение_слоя.сформировать(файлы[слой['поручение']].decode('utf-8'),слой,база,блок,проверка_прав=True)
    хранение.требовать(ожидаемый==поручение['текст'], 'Полное поручение проверки прав не совпало с C')
    исполнитель=SimpleNamespace(хранилище=хранилище)
    остановка_ребёнка.проверить_дерево(исполнитель,{'корень':str(корень)},база)
    результат=прочитать(корень,задача,база,источник)
    хранение.требовать(нативное_назначение.прочитать(источник)==поручение
        and прочитать(корень,задача,база,источник)==результат, 'Права и поручение не образуют неизменный начальный префикс')
    остановка_ребёнка.проверить_дерево(исполнитель,{'корень':str(корень)},база)
    проверить_код(корень,база)
    результат={**результат,'поручение':поручение['источник']}
    return {**результат,'sha256':хранение.хэш(результат)}


def проверить_первого(исполнитель, запись, состояние, слой, источник):
    план=запись['план']; описание=next(с for с in план['описание']['слои'] if с['слой']==слой)
    if not описание['зависит_от']:
        хранение.требовать(источник is None,'Источнику первого слоя не назначен предшествующий ребёнок')
        return
    хранение.требовать(len(описание['зависит_от'])==1 and источник is not None,'Нет первичного источника зависимого ребёнка')
    первый=описание['зависит_от'][0]; попытка=состояние['попытки'].get(план['попытки'][первый])
    наблюдение=запись['наблюдения'][первый]
    хранение.требовать(type(попытка) is dict and type(наблюдение) is dict
        and попытка['аргументы']==план['аргументы'][первый] and попытка['база']==план['координатор']['HEAD']
        and попытка['аргументы_sha256']==хранение.хэш(попытка['аргументы']) and type(попытка['ответ']) is dict,
        'Нет первой настоящей попытки, ответа и раннего наблюдения')
    ответ=попытка['ответ']; задача=наблюдение['задача']; база=запись['смысл']['постановка']['коммит']
    хранение.требовать(not ответ.get('противоречивые_идентификаторы') and ответ.get('threadId') in (None,задача)
        and bool(ответ.get('threadId') or ответ.get('clientThreadId'))
        and type(ответ.get('сырой_ответ')) is dict and ответ['сырой_ответ'].get('isError') is not True,
        'Нет непротиворечивого принятого ответа первой задачи')
    def перечитать():
        раннее=постановка.прочитать_подтверждение(Path(наблюдение['корень']),задача,база,источник)
        поручение=постановка.проверить_нативное_поручение(источник,исполнитель.задача,попытка['аргументы']['prompt'],кодирование='xml-v1')
        return {**раннее,'поручение':поручение}
    хранение.требовать(наблюдение['схема']=='fum.начальная-база-задачи.2' and перечитать()==наблюдение,
        'Первоначальная запись или поручение первой задачи сдвинулись')
    права=прочитать(наблюдение['корень'],задача,база,источник)
    хранение.требовать(права['источник']==наблюдение['источник'] and перечитать()==наблюдение
        and прочитать(наблюдение['корень'],задача,база,источник)==права,
        'Наблюдение и права не относятся к одному начальному префиксу')

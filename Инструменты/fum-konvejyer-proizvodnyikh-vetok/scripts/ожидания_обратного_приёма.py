"""Последний отдельный wait каждого ребёнка после его единственного send."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import приём_направления as хранение


def проверить(нативный, номера, отправки, *, последовательные_приёмы=True):
    хранение.требовать(type(последовательные_приёмы) is bool, 'Неизвестный режим порядка приёмов')
    хранение.требовать(нативный['схема'] == 'fum.наблюдённые-вызовы-запуска.2'
        and нативный['источник']['начало'] == нативный['начальная_граница'],
        'Нужна полная история с интервалами runtime')
    хранение.требовать(type(отправки) is dict and len(отправки) == 2
        and all(хранение.идентификатор_задачи(з) for з in отправки)
        and all(хранение.текст(н) for н in отправки.values())
        and len(set(отправки.values())) == 2, 'Нужны две единственные отправки детям')
    хранение.поля(номера, отправки)
    хранение.требовать(all(хранение.текст(н) for н in номера.values())
        and len(set(номера.values())) == 2, 'Нужны разные ожидания детей')
    возобновления = нативный['возобновления']
    хранение.требовать(len(возобновления) == 2
        and all(в['инструмент'] == 'send_message_to_thread' for в in возобновления)
        and {в['аргументы'].get('threadId'): в['id'] for в in возобновления} == отправки,
        'Лишний, перенесённый или подменённый send обратного приёма')
    по_детям = {в['аргументы']['threadId']: в for в in возобновления}
    порядок = sorted(возобновления, key=lambda в: в['источник']['начало'])
    первый, второй = порядок
    хранение.требовать(первый['источник']['конец'] <= второй['источник']['начало']
        and первый['интервал']['конец_мс'] < второй['интервал']['начало_мс'],
        'Отправки обратного приёма должны быть последовательными')
    for создание in нативный['вызовы']:
        хранение.требовать(создание['инструмент'] == 'create_thread'
            and создание['источник']['конец'] <= первый['источник']['начало']
            and создание['интервал']['конец_мс'] < первый['интервал']['начало_мс'],
            'Позднее создание не является первоначальным запуском')
    выбранные = {}
    for ребёнок, номер in номера.items():
        адресованные = [о for о in нативный['ожидания']
            if ребёнок in {ц.get('threadId') for ц in о['аргументы']['targets']}]
        хранение.требовать(адресованные and адресованные[-1]['id'] == номер,
            'Нужно последнее адресованное ребёнку ожидание')
        ожидание = адресованные[-1]
        хранение.требовать(len(ожидание['аргументы']['targets']) == 1,
            'Обратный приём требует одиночных целей ожидания')
        отправка = по_детям[ребёнок]
        хранение.требовать(отправка['источник']['конец'] <= ожидание['источник']['начало']
            and отправка['интервал']['конец_мс'] < ожидание['интервал']['начало_мс'],
            'Ожидание началось до завершения собственного send либо перекрывает его')
        выбранные[ребёнок] = ожидание
    порядок = sorted(выбранные.values(), key=lambda о: о['источник']['начало'])
    первое, второе = порядок
    хранение.требовать(первое['источник']['конец'] <= второе['источник']['начало']
        and первое['интервал']['конец_мс'] <= второе['интервал']['начало_мс'],
        'Раздельные ожидания должны быть последовательными')
    if последовательные_приёмы:
        первое_ожидание = выбранные[первый['аргументы']['threadId']]
        хранение.требовать(первое_ожидание['источник']['конец'] <= второй['источник']['начало']
            and первое_ожидание['интервал']['конец_мс'] < второй['интервал']['начало_мс'],
            'Второй send начался до завершения первого ожидания')
    return выбранные

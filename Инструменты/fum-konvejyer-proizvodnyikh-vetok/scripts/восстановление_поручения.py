"""Предложить точные байты исправления; не читать и не изменять хранилища."""
import hashlib
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-struktura-papok-zaprosov/scripts'))
import request_folder_layout as каркас
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-svezhestj-markdown/scripts'))
import ограды_цитат


# Точный старый распознаватель из 5419ed11bfbe484baa6d133dc5bd0c574a89d794.
# Он нужен только для доказательства единственного известного удаления.
СТАРАЯ_МЕТКА = re.compile(
    r'\n?<!-- FUM-MD-RECENCY:BEGIN -->\n'
    r'<!-- last-content-edit: (?P<timestamp>[^>]+) -->\n'
    r'<!-- content-sha256: sha256:(?P<digest>[0-9a-f]{64}) -->\n'
    r'<!-- FUM-MD-RECENCY:END -->\n?$', re.MULTILINE)
ПОЛЕ = '## Текст запроса\n\n'
СЛЕДУЮЩЕЕ_ПОЛЕ = b'## ' + 'Идентификатор сеанса Codex\n'.encode('utf-8')


def _текст(данные):
    if not isinstance(данные, bytes):
        raise ValueError('Ожидались исходные байты UTF-8/LF')
    try:
        текст = данные.decode('utf-8')
    except UnicodeDecodeError as ошибка:
        raise ValueError('Ожидались исходные байты UTF-8/LF') from ошибка
    if '\r' in текст or not текст.endswith('\n'):
        raise ValueError('Поддерживается только UTF-8/LF с последним LF')
    return текст


def _отпечаток(данные):
    return hashlib.sha256(данные).hexdigest()


def предложить(документ, поручение):
    """Вернуть байты и свидетельство без допуска записи или подмены назначения.

    Принимается целое поручение либо удаление первого блока ровно старым
    распознавателем. Происхождение поручения и неизменность Git проверяются
    отдельным вызывающим контуром; эта функция не выдаёт таких свидетельств.
    """
    текст, исходник = _текст(документ), _текст(поручение)
    маска, незакрыта = ограды_цитат.маскировать(текст)
    заголовки = list(re.finditer(r'(?m)^##[ \t]+Текст запроса[ \t]*(?:#+[ \t]*)?\n', маска))
    if незакрыта or len(заголовки) != 1:
        raise ValueError('Требуется единственное внешнее поле текста запроса')
    начало = len(текст[:заголовки[0].start()].encode('utf-8'))
    ограда = каркас._fence_for(исходник)
    префикс = (ПОЛЕ + ограда + 'text\n').encode('utf-8')
    суффикс = ('\n' + ограда + '\n\n').encode('utf-8')
    целое = префикс + поручение + суффикс
    вставка = None
    результат = документ
    if not документ.startswith(целое + СЛЕДУЮЩЕЕ_ПОЛЕ, начало):
        совпадение = СТАРАЯ_МЕТКА.search(исходник)
        if совпадение is None:
            raise ValueError('Поле не соответствует известному удалению')
        до = исходник[:совпадение.start()].encode('utf-8')
        удалённое = совпадение.group().encode('utf-8')
        после = исходник[совпадение.end():].encode('utf-8')
        повреждённое = префикс + до + после + суффикс
        if not документ.startswith(повреждённое + СЛЕДУЮЩЕЕ_ПОЛЕ, начало):
            raise ValueError('Поле не соответствует известному удалению')
        смещение = начало + len(префикс) + len(до)
        результат = документ[:смещение] + удалённое + документ[смещение:]
        вставка = {'начало': смещение, 'байтов': len(удалённое),
                   'переводов_строки': удалённое.count(b'\n'), 'sha256': _отпечаток(удалённое),
                   'префикс_sha256': _отпечаток(документ[:смещение]),
                   'суффикс_sha256': _отпечаток(документ[смещение:])}
    return результат, {
        'схема': 'fum.предложение-восстановления-поручения.1',
        'до_sha256': _отпечаток(документ), 'после_sha256': _отпечаток(результат),
        'поручение_sha256': _отпечаток(поручение), 'вставка': вставка,
        'повтор': вставка is None, 'разрешение_записи': False}

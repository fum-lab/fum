"""Ограниченное чтение и повторная сверка; не создаёт каталогов или замков."""
import hashlib
import os
from pathlib import Path
import stat
import unicodedata

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import эпизод_приёма as эпизод
хранение = эпизод.хранение


def _метка(с, *, каталог=False):
    поля = ('st_dev', 'st_ino', 'st_mode', 'st_uid') if каталог else (
        'st_dev', 'st_ino', 'st_mode', 'st_uid', 'st_nlink', 'st_size', 'st_mtime_ns', 'st_ctime_ns')
    return tuple(getattr(с, к) for к in поля)


def _абсолютный(значение):
    хранение.требовать(type(значение) is str and значение and '\0' not in значение
        and '\\' not in значение and Path(значение).is_absolute()
        and str(Path(значение)) == значение and '..' not in Path(значение).parts,
        'Нужен канонический абсолютный путь')
    return Path(значение)


class СнимокФайлов:
    def __init__(сам):
        сам.каталоги, сам.файлы, сам.составы = {}, {}, {}

    def _каталоги(сам, путь, база):
        хранение.требовать(путь.is_relative_to(база) and путь != база, 'Файл вне приватной базы')
        хранение.требовать(база == база.resolve(), 'Нужна физическая приватная база')
        for к in reversed(путь.parents):
            с = к.lstat()
            хранение.требовать(stat.S_ISDIR(с.st_mode), 'Не каталог или ссылка в приватном пути')
            if к == база or к.is_relative_to(база):
                хранение.требовать(с.st_uid == os.getuid() and с.st_mode & 0o077 == 0,
                    'Каталог должен быть приватным и принадлежать владельцу')
            if к != Path(к.anchor):
                имя = unicodedata.normalize('NFC', к.name)
                хранение.требовать(any(unicodedata.normalize('NFC', п.name) == имя
                    for п in к.parent.iterdir()), 'Регистр пути не совпал с каталогом')
            хранение.требовать(not os.path.lexists(к / '.git')
                and not ((к / 'objects').is_dir() and os.path.lexists(к / 'HEAD')),
                'Приватный файл запрещён внутри Git')
            метка = _метка(с, каталог=True)
            хранение.требовать(сам.каталоги.get(к, метка) == метка, 'Подменён каталог при чтении')
            сам.каталоги[к] = метка

    def _снять(сам, путь, база, предел):
        сам._каталоги(путь, база)
        до = путь.lstat()
        хранение.требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1
            and до.st_uid == os.getuid() and до.st_mode & 0o077 == 0
            and 0 <= до.st_size <= предел, 'Нужен ограниченный приватный обычный файл')
        имя = unicodedata.normalize('NFC', путь.name)
        хранение.требовать(any(unicodedata.normalize('NFC', п.name) == имя
            for п in путь.parent.iterdir()), 'Регистр файла не совпал с именем')
        with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK), 'rb') as поток:
            хранение.требовать(_метка(os.fstat(поток.fileno())) == _метка(до), 'Подменён открытый файл')
            сырой = поток.read(предел + 1)
            хранение.требовать(len(сырой) == до.st_size and len(сырой) <= предел
                and _метка(os.fstat(поток.fileno())) == _метка(до), 'Файл изменился во время чтения')
        хранение.требовать(_метка(путь.lstat()) == _метка(до), 'Подменён файл после чтения')
        сам._каталоги(путь, база)
        return сырой, _метка(до)

    def прочитать(сам, имя, путь, база, *, json=True, предел=1048576):
        путь, база = _абсолютный(str(путь)), _абсолютный(str(база))
        сырой, метка = сам._снять(путь, база, предел)
        sha = hashlib.sha256(сырой).hexdigest()
        хранение.требовать(имя not in сам.файлы, 'Повтор имени свидетельства')
        сам.файлы[имя] = (путь, база, предел, метка, sha)
        if not json: return сырой
        значение = хранение.разобрать(сырой)
        хранение.требовать(хранение.байты(значение) == сырой, 'Неканонический приватный JSON')
        return значение

    def состав(сам, путь, ожидаемые):
        имена = frozenset(п.name for п in путь.iterdir())
        хранение.требовать(имена == frozenset(ожидаемые), 'Неполный или лишний состав свидетельства')
        сам.составы[путь] = имена

    def сверить(сам):
        for путь, метка in сам.каталоги.items():
            хранение.требовать(_метка(путь.lstat(), каталог=True) == метка,
                'Сдвинулся каталог перед возвратом')
        for путь, имена in сам.составы.items():
            хранение.требовать(frozenset(п.name for п in путь.iterdir()) == имена,
                'Сдвинулся состав свидетельства')
        for путь, база, предел, метка, sha in сам.файлы.values():
            сырой, теперь = сам._снять(путь, база, предел)
            хранение.требовать(теперь == метка and hashlib.sha256(сырой).hexdigest() == sha,
                'Сдвинулись байты свидетельства перед возвратом')
        return {имя: запись[4] for имя, запись in сам.файлы.items()}

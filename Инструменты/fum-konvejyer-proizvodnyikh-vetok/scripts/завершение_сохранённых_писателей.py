"""Терминал двух остановленных писателей без изменения их refs и файлов."""
import copy
import hashlib
from pathlib import Path

import приём_направления as хранение
from отложенные_назначения import манифест_коммита, извлечь_ответ
import область_писателя
import нативные_вызовы
import последнее_ожидание
import сохранённый_писатель
import терминал_запуска

КОД = {Path(м.__file__).resolve(): hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
       for м in (область_писателя, нативные_вызовы, последнее_ожидание, сохранённый_писатель, терминал_запуска,
                 сохранённый_писатель.остановка_ребёнка, сохранённый_писатель.пакет_незавершённого,
                 сохранённый_писатель.хранилище_незавершённого)}
КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def _координатор(исполнитель, вход, план, состояние):
    текущий = исполнитель.хранилище._наблюдать_владельца()
    прежний = план['координатор']
    хранение.требовать(текущий == вход['координатор'] and текущий['ref'] == прежний['ref']
                       and текущий['путь'] == прежний['путь'] and текущий['задача'] == прежний['задача'],
                       'Сменился координатор остановленного поколения')
    хранение.требовать(состояние['писатели'].get(str(исполнитель.корень))
                       == {'задача': исполнитель.задача, 'ref': текущий['ref']}, 'Не подтверждён писатель координатора')
    хранение.гит(исполнитель.корень, 'merge-base', '--is-ancestor', прежний['HEAD'], текущий['HEAD'])
    return текущий


def _план(исполнитель, вход, состояние):
    хранение.поля(вход, {'схема', 'запуск', 'план_sha256', 'координатор', 'источник', 'ожидание', 'слои', 'свидетельство_координатора'})
    хранение.требовать(вход['схема'] == 'fum.завершение-неудачного-запуска.2', 'Неизвестный переход с пакетами')
    запись = исполнитель._прочитать(состояние, вход['запуск']); план = запись['план']
    хранение.требовать(план['sha256'] == вход['план_sha256']
                       and запись['смысл']['схема'] in {'fum.запуск-двух-слоёв.2', 'fum.запуск-двух-слоёв.3'}
                       and len(запись['наблюдения']) == 2 and all(type(н) is dict for н in запись['наблюдения'].values()),
                       'Нужны два наблюдённых писателя полного назначения')
    попытки = {слой: состояние['попытки'].get(ключ) for слой, ключ in план['попытки'].items()}
    история = хранение.хэш({'запись': запись, 'попытки': попытки})
    прежний = терминал_запуска.прочитать(состояние, вход['запуск'])
    if прежний is not None:
        хранение.требовать(прежний['схема'] == терминал_запуска.СХЕМА_С_ПАКЕТАМИ
                           and прежний['вход_sha256'] == хранение.хэш(вход) and прежний['история_sha256'] == история,
                           'Повтор изменил терминал или историю')
        return copy.deepcopy(прежний), []
    координатор = _координатор(исполнитель, вход, план, состояние)
    исполнитель._инструменты(координатор['HEAD'])
    for путь, хэш in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == хэш, 'Код завершения изменился')
    аттестация = {'задача': исполнитель.задача, 'единственный_координатор': True,
                 'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}
    хранение.требовать(вход['свидетельство_координатора'] == аттестация, 'Нет кооперативной аттестации координатора')
    хранение.требовать(type(вход['слои']) is dict and set(вход['слои']) == set(попытки), 'Неполный состав остановленных детей')
    база = план['координатор']['HEAD']; смысл = запись['смысл']
    файлы = манифест_коммита(исполнитель.корень, база, смысл['постановка']['файлы'])
    хранение.требовать(смысл['план'] in файлы and смысл['назначение'] in файлы
                       and хранение.разобрать(файлы[смысл['план']]) == план['описание'], 'Подменён манифест назначения')
    области = область_писателя.каталоги_назначения(исполнитель.корень, база, исполнитель.задача, смысл['план'],
        план['описание'], хранение.разобрать(файлы[смысл['назначение']]))
    дети = [н['задача'] for н in запись['наблюдения'].values()]
    корни = [н['корень'] for н in запись['наблюдения'].values()]
    хранение.требовать(len(set(дети)) == len(set(корни)) == 2, 'Повтор ребёнка или дерева')
    for слой, попытка in попытки.items():
        хранение.требовать(type(попытка) is dict and попытка['аргументы'] == план['аргументы'][слой]
                           and попытка['база'] == база, 'Изменена попытка ребёнка')
    нативный = нативные_вызовы.прочитать(вход['источник'], исполнитель.задача,
        аргументы=[п['аргументы'] for п in попытки.values()], ожидания=дети, интервалы=True)
    ожидание = последнее_ожидание.проверить(нативный, вход['ожидание'], дети)
    результаты, сверки = {}, []
    for слой, завершение in вход['слои'].items():
        попытка = попытки[слой]
        вызовы = [в for в in нативный['вызовы'] if в['аргументы'] == попытка['аргументы']]
        хранение.требовать(len(вызовы) == 1 and извлечь_ответ(вызовы[0]['ответ']) == попытка['ответ'],
                           'Нет единственного точного вызова и сохранённого ответа')
        ответ = попытка['ответ']
        хранение.требовать(not ответ.get('противоречивые_идентификаторы')
                           and ответ.get('threadId') in (None, запись['наблюдения'][слой]['задача']), 'Ответ противоречит ребёнку')
        ветка = next(с['ветка'] for с in план['описание']['слои'] if с['слой'] == слой)
        аргументы = (исполнитель, завершение, запись['наблюдения'][слой], попытка, база, области[слой], ветка, ожидание)
        результаты[слой] = сохранённый_писатель.проверить(*аргументы)
        сверки.append((слой, аргументы))
    хранение.требовать(_координатор(исполнитель, вход, план, состояние) == координатор, 'Координатор изменился')
    квитанция = {'схема': терминал_запуска.СХЕМА_С_ПАКЕТАМИ, 'запуск': вход['запуск'], 'план_sha256': план['sha256'],
        'вход_sha256': хранение.хэш(вход), 'история_sha256': история, 'координатор': координатор,
        'слои': результаты, 'источник': нативный['источник'], 'свидетельство_координатора': аттестация,
        'отсутствие_незаписанного_вызова_доказано': False,
        'ожидание': {'id': ожидание['id'], 'источник': ожидание['источник'], 'интервал': ожидание['интервал']}}
    return {**квитанция, 'sha256': хранение.хэш(квитанция)}, сверки


def предпросмотр(исполнитель, вход):
    return _план(исполнитель, вход, исполнитель.хранилище.прочитать())[0]


def завершить(исполнитель, вход, ожидаемый_sha256):
    with исполнитель.хранилище.изменить() as состояние:
        результат, сверки = _план(исполнитель, вход, состояние)
        хранение.требовать(результат['sha256'] == ожидаемый_sha256, 'Изменён просмотренный переход с пакетами')
        ключ = терминал_запуска.ключ(вход['запуск'])
        if ключ not in состояние['приёмы']:
            for слой, аргументы in сверки:
                хранение.требовать(сохранённый_писатель.проверить(*аргументы) == результат['слои'][слой],
                                   'Сохранённый писатель изменился перед записью терминала')
            исполнитель.хранилище.проверить_владельца_под_замком(состояние,
                ожидаемый_коммит=вход['координатор']['HEAD'], ожидаемая_ветка=вход['координатор']['ref'])
            состояние['приёмы'][ключ] = результат
        return copy.deepcopy(результат)

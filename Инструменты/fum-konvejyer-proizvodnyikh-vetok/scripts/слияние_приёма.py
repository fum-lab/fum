"""Внутренняя связь проверенного намерения с одним Git-эффектом; без CLI."""
from contextlib import contextmanager
import hashlib
from pathlib import Path
import time

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import эпизод_приёма as эпизод
import доставка_гит as гит
import доставка_план
from обратная_доставка import Доставка

хранение = эпизод.хранение


class _ДоставкаПриёма(Доставка):
    def __init__(сам, основание, план, реестр, перечитать):
        сам.основание, сам.перечитать = основание, перечитать
        блок = основание['поручение']
        каталог = эпизод.путь_эпизода(основание).with_suffix('.доставка')
        super().__init__(план, блок['корень'], блок['исполнитель'], реестр, каталог)
        источник = план['источник']
        хранение.требовать(блок['план'] == план['идентификатор']
            and источник['срез'] == блок['срез'] == основание['срез']
            and источник['коммит'] == блок['источник_приёмки']
            and источник['владелец'] == блок['корневая_задача']
            and источник['дерево'] == основание['дерево'], 'Другой план или срез намерения')
        хранение.требовать(сам.цель['владелец'] == блок['исполнитель']
            and сам.цель['ref'] == блок['ref'] and сам.цель['коммит'] == блок['исходный_коммит'],
            'Получатель не совпал с намерением')
        хранение.требовать(блок['исходный_коммит'] != блок['срез']
            and гит.предок(сам.корень, блок['база'], блок['исходный_коммит'])
            and гит.предок(сам.корень, блок['исходный_коммит'], блок['срез']),
            'Нужна история C → H → S с H != S')
        сам._свидетельство(источник)

    def _свидетельство(сам, описание):
        приёмка = доставка_план.прочитать_приёмку(сам.корень, описание['коммит'],
            описание['срез'], описание['приёмка'])
        хранение.требовать(приёмка == сам.основание['приёмка'], 'Изменено свидетельство намерения')
        return приёмка

    def _проверить_назначение_слияния(сам):
        # Явное поручение этого режима доставляет и историю при равных деревьях.
        хранение.требовать(сам.цель['коммит'] != сам.основание['срез']
            and гит.предок(сам.корень, сам.цель['коммит'], сам.основание['срез']),
            'Получатель не является строгим предком назначенного среза')

    def _принять_источник(сам, описание):
        # Свежий нативный допуск обязателен перед первым эффектом, но не при
        # восстановлении уже наблюдаемого эффекта по сохранённой квитанции.
        актуальное = сам.перечитать()
        эпизод.проверить_основание(актуальное)
        хранение.требовать(актуальное == сам.основание, 'Сдвинулся допуск перед слиянием')
        return {**описание, **сам._свидетельство(описание)}

    def _восстановить(сам, данные):
        хранение.требовать(данные['план'] == сам.план['идентификатор']
            and данные['корень'] == str(сам.корень) and данные['ref'] == сам.цель['ref']
            and данные['владелец'] == сам.задача and данные['до'] == сам.цель['коммит']
            and данные['источник'] == сам.основание['срез']
            and данные['дерево'] == сам.основание['дерево'] and данные.get('отчёт') is None,
            'Квитанция другого слияния или отчётного этапа')
        return super()._восстановить(данные)


class СлияниеПриёма:
    """Доверенный внутренний вызывающий передаёт настоящий читающий допуск.

    Произвольный объект с хэшем и callback не заменяют нативную авторизацию.
    Проверка/коммит новой пары Журнала принадлежат следующему отдельному слою.
    """
    def __init__(сам, основание, план, реестр, перечитать):
        сам.основание = хранение.разобрать(хранение.байты(основание))
        эпизод.проверить_основание(сам.основание)
        сам._доставка = _ДоставкаПриёма(сам.основание,
            хранение.разобрать(хранение.байты(план)), реестр, перечитать)
        сам.профиль = []

    @contextmanager
    def _метка(сам, имя):
        начало = time.monotonic_ns()
        исход = 'отказ'
        try:
            yield
            исход = 'успех'
        finally:
            сам.профиль.append({'стадия': имя, 'исход': исход, 'родитель': None,
                'длительность_наносекунды': time.monotonic_ns() - начало})

    @contextmanager
    def _замок(сам):
        with сам._метка('владелец и инфраструктура замка'):
            сам._доставка._владелец()
            путь = эпизод.путь_эпизода(сам.основание)
            эпизод.проверить_каталоги(путь)
            хранение.создать_каталоги(путь.parent, Path(путь.anchor), права=0o700)
            эпизод.проверить_каталоги(путь)
        with эпизод.файлы._замок(путь.with_suffix('.исполнение.json')):
            yield

    def применить(сам):
        with сам._замок():
            with сам._метка('неизменяемое намерение'):
                прежнее = эпизод.прочитать(сам.основание)
                if прежнее is None:
                    # До намерения исключаются грязное дерево и иной владелец.
                    сам._доставка._проверить_назначение_слияния()
                    подготовка = сам._доставка._новая()
                    гит.исключить_коллизии(сам._доставка.корень, подготовка['источник'], подготовка['защищённые'])
                    каталог = сам._доставка.хранилище.каталог
                    хранение.создать_каталоги(каталог, каталог.parent, права=0o700)
                    эпизод.начать(сам.основание, сам._доставка.перечитать)
                else:
                    # Отсутствие квитанции не отличает первый обрыв от потери
                    # истории после исполнения и отмены merge; повтор закрыт.
                    восстановленное = сам._доставка.состояние()
                    if восстановленное['стадия'] != 'подготовлено':
                        return восстановленное
            with сам._метка('применение или восстановление Git'):
                return сам._доставка.применить()

    def состояние(сам):
        with сам._замок():
            with сам._метка('восстановление состояния'):
                хранение.требовать(эпизод.прочитать(сам.основание) is not None,
                    'Нет сохранённого намерения приёма')
                return сам._доставка.состояние()

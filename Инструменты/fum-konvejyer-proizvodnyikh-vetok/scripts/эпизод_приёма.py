"""Неизменяемое намерение приёма; хранение не разрешает Git-эффект или повтор."""
import hashlib
import os
from pathlib import Path
import stat
import sys

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

ИНСТРУМЕНТЫ = Path(__file__).resolve().parents[2]
for КАТАЛОГ in ('fum-reyestr-planirovaniya', 'fum-svyaznostj-rabochej-sessii'):
    sys.path.insert(0, str(ИНСТРУМЕНТЫ / КАТАЛОГ / 'scripts'))
import приём_направления as хранение
import сообщения_задачи as файлы

КОРЕНЬ_СОСТОЯНИЯ = (Path('/Users/Shared') / ('FUM-private-' + str(os.getuid()))
    if sys.platform == 'darwin' else Path.home() / '.local/state/FUM') / 'эпизоды-приёма'


def проверить_основание(основание):
    хранение.поля(основание, {'схема', 'назначение', 'поручение', 'эпизод', 'срез', 'дерево',
        'приёмка', 'нативный_приём', 'журнал', 'проверка', 'разрешение_записи', 'sha256'})
    хранение.требовать(основание['схема'] == 'fum.основание-дочернего-приёма.1'
        and основание['разрешение_записи'] is False, 'Нужно читающее основание приёма')
    тело = {к: з for к, з in основание.items() if к != 'sha256'}
    хранение.требовать(хранение.хэш(тело) == основание['sha256'], 'Изменён отпечаток основания')
    поручение = основание['поручение']
    хранение.требовать(type(поручение) is dict
        and хранение.идентификатор_задачи(поручение.get('исполнитель'))
        and хранение.шестнадцатеричный(поручение.get('назначение_sha256')),
        'Нужно первоначальное назначение и UUID исполнителя')
    хранение.требовать(хранение.хэш(основание['назначение']) == поручение['назначение_sha256'],
        'Подменено первоначальное назначение')
    ключ = хранение.хэш({к: поручение[к] for к in ('назначение_sha256', 'исполнитель')})
    хранение.требовать(основание['эпизод'] == ключ, 'Подменён адрес эпизода')
    return поручение['исполнитель'], ключ


def путь_эпизода(основание):
    задача, ключ = проверить_основание(основание)
    корень = Path(КОРЕНЬ_СОСТОЯНИЯ)
    хранение.требовать(корень.is_absolute() and корень.resolve() == корень,
        'Нужен канонический корень приватных эпизодов')
    путь = корень / задача / (ключ + '.json')
    for предок in путь.parents:
        хранение.требовать(not os.path.lexists(предок / '.git')
            and not ((предок / 'objects').is_dir() and (предок / 'HEAD').is_file()),
            'Приватный эпизод находится внутри Git')
    хранение.безопасный_путь(путь)
    return путь


def прочитать_файл(путь):
    хранение.безопасный_путь(путь)
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(дескриптор, 'rb') as поток:
        состояние = os.fstat(поток.fileno())
        хранение.требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1
            and состояние.st_uid == os.getuid() and состояние.st_mode & 0o077 == 0,
            'Нужен приватный обычный файл эпизода')
        данные = поток.read()
    значение = хранение.разобрать(данные)
    хранение.требовать(хранение.байты(значение) == данные, 'Не канонические байты эпизода')
    return значение


def проверить_каталоги(путь):
    for каталог in (Path(КОРЕНЬ_СОСТОЯНИЯ), путь.parent):
        хранение.безопасный_путь(каталог, каталог=True)
        if каталог.exists():
            сведения = каталог.stat()
            хранение.требовать(сведения.st_uid == os.getuid() and сведения.st_mode & 0o077 == 0,
                'Каталог эпизода должен быть приватным и принадлежать владельцу')


def прочитать(основание):
    """Ничего не создаёт; незавершённая пара сохраняет отказ до разбора владельцем."""
    путь = путь_эпизода(основание)
    проверить_каталоги(путь)
    метка = путь.with_suffix('.начато.json')
    хранение.безопасный_путь(метка)
    наличие = (os.path.lexists(метка), os.path.lexists(путь))
    if наличие == (False, False):
        return None
    хранение.требовать(наличие == (True, True), 'Потеряно или прервано начатое намерение приёма')
    ожидаемая = {'схема': 'fum.начатый-эпизод-приёма.1', 'эпизод': основание['эпизод'],
        'основание_sha256': основание['sha256']}
    хранение.требовать(прочитать_файл(метка) == ожидаемая, 'Сохранён другой допуск того же эпизода')
    конверт = прочитать_файл(путь)
    хранение.поля(конверт, {'данные', 'sha256'})
    данные = конверт['данные']
    хранение.требовать(хранение.хэш(данные) == конверт['sha256'], 'Повреждён отпечаток намерения')
    ожидаемое = {'схема': 'fum.намерение-дочернего-приёма.1', 'эпизод': основание['эпизод'],
        'основание': основание, 'разрешение_записи': False}
    хранение.требовать(данные == ожидаемое, 'Изменено сохранённое намерение приёма')
    return данные


def начать(основание, перечитать):
    """Зафиксировать уже проверенный допуск, повторно прочитав его до первой записи.

    Повтор возвращает прежнее намерение без нового допуска старого H. Это только
    чтение свидетельства: исполнитель обязан отдельно проверить фактический
    Git-эффект и стадию; этот модуль не выполняет и не повторяет слияние.
    """
    основание = хранение.разобрать(хранение.байты(основание))
    путь = путь_эпизода(основание)
    проверить_каталоги(путь)
    # Каталоги и замок — инфраструктура хранения, ещё не начало Git-эффекта.
    # Повтор закрепляет и родительские записи каталогов, созданных до прерывания.
    # Существующие каталоги не меняют режим; отсутствующие создаются приватными.
    хранение.создать_каталоги(путь.parent, Path(путь.anchor), права=0o700)
    проверить_каталоги(путь)
    with файлы._замок(путь):
        прежнее = прочитать(основание)
        if прежнее is not None:
            return прежнее
        актуальное = перечитать()
        проверить_основание(актуальное)
        хранение.требовать(актуальное == основание, 'Сдвинулся допуск до записи намерения')
        данные = {'схема': 'fum.намерение-дочернего-приёма.1', 'эпизод': основание['эпизод'],
            'основание': основание, 'разрешение_записи': False}
        метка = {'схема': 'fum.начатый-эпизод-приёма.1', 'эпизод': основание['эпизод'],
            'основание_sha256': основание['sha256']}
        хранение.установить(путь.with_suffix('.начато.json'), хранение.байты(метка))
        хранение.установить(путь, хранение.байты({'данные': данные, 'sha256': хранение.хэш(данные)}))
        return прочитать(основание)

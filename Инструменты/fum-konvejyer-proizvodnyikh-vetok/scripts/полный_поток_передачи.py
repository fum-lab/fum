"""Не скрывать управление, уже попавшее в начальный снимок передачи."""
import снимок_нативного_источника as снимок
import контроль_первичного_потока

хранение = снимок.хранение


def проверить(сырые, граница, *, транспорт='create_thread'):
    хранение.требовать(транспорт in {'create_thread', 'send_message_to_thread'}, 'Неизвестный транспорт границы')
    строки = сырые.splitlines(keepends=True)
    конец = 0
    исходный = None
    контроль = контроль_первичного_потока.КонтрольПервичногоПотока()
    история = снимок.ИсторияНачальногоКонтекста()
    транспорты = []
    for строка in строки:
        начало = конец; конец += len(строка)
        запись = хранение.разобрать(строка)
        хранение.требовать(type(запись) is dict and type(запись.get('payload')) is dict,
            'Неизвестная запись первоначального потока')
        данные = запись['payload']
        тип, вид = запись.get('type'), данные.get('type')
        сжатие = история.проверить(запись)
        копия = контроль.проверить(запись)
        if тип == 'response_item' and вид == 'function_call_output' and данные.get('name') in снимок.ТРАНСПОРТЫ:
            транспорты.append(данные['name'])
            разрешённые = (['create_thread'],) if транспорт == 'create_thread' else (
                ['create_thread'], ['send_message_to_thread'], ['create_thread', 'send_message_to_thread'])
            хранение.требовать(конец <= граница and транспорты in разрешённые,
                'До снимка получено новое управляющее поручение; нужен разбор координатора')
        if конец == граница:
            хранение.требовать(тип == 'response_item' and вид == 'function_call_output'
                and данные.get('name') == транспорт, 'Граница не завершает первоначальное поручение')
            исходный = данные['output']
        if начало < граница:
            транспортный_ответ = (тип == 'response_item' and вид == 'function_call_output'
                and данные.get('name') in снимок.ТРАНСПОРТЫ)
            if история.сжатие_проверено and not сжатие and not копия and not транспортный_ответ:
                снимок.проверить_запись(запись)
            continue
        if not копия and not сжатие:
            снимок.проверить_запись(запись)
    хранение.требовать(исходный is not None, 'Нет точной границы первоначального поручения')

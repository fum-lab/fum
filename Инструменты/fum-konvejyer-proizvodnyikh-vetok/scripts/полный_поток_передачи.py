"""Не скрывать управление, уже попавшее в начальный снимок передачи."""
import снимок_нативного_источника as снимок

хранение = снимок.хранение


def проверить(сырые, граница):
    строки = сырые.splitlines(keepends=True)
    конец = 0
    исходный = None
    завершение_поручения = False
    for строка in строки:
        начало = конец; конец += len(строка)
        запись = хранение.разобрать(строка)
        хранение.требовать(type(запись) is dict and type(запись.get('payload')) is dict,
            'Неизвестная запись первоначального потока')
        данные = запись['payload']
        тип, вид = запись.get('type'), данные.get('type')
        хранение.требовать(not (тип == 'event_msg' and вид in {'user_message', 'turn_aborted'}),
            'До снимка получено новое управляющее событие; нужен разбор координатора')
        if конец == граница:
            хранение.требовать(тип == 'response_item' and вид == 'function_call_output'
                and данные.get('name') == 'create_thread', 'Граница не завершает первоначальное поручение')
            исходный = данные['output']
        if начало < граница:
            continue
        элемент = данные.get('item')
        if тип == 'event_msg' and вид == 'item_completed' and type(элемент) is dict \
                and элемент.get('type') == 'FunctionCallOutput' and элемент.get('name') == 'create_thread':
            # Нативное событие завершения повторяет тот же транспорт, не новое поручение.
            хранение.требовать(not завершение_поручения and исходный is not None
                and элемент.get('namespace') == 'codex_app' and элемент.get('output') == исходный,
                'Подменено или повторено завершение первоначального поручения')
            завершение_поручения = True
        else:
            снимок.проверить_хвост(строка)
    хранение.требовать(исходный is not None, 'Нет точной границы первоначального поручения')

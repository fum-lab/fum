"""Связать неизменяемую приёмку с назначенным получателем; без разрешения записи."""
import hashlib
from pathlib import Path
import re
import unicodedata

import дочернее_назначение
import нативный_приём
import приём_направления as хранение
import доставка_гит as гит
import доставка_план
import доставка_отчёта
import отложенные_назначения

НАЧАЛО = 'Проверь адресный приём интеграции по первоначальному назначению.\n<fum_layer_reception>\n'
КОНЕЦ = '</fum_layer_reception>\n'
ПОЛЯ = {'схема', 'корневая_задача', 'исполнитель', 'база', 'назначение_sha256', 'слой',
        'корень', 'ref', 'исходный_коммит', 'срез', 'источник_приёмки', 'план', 'журнал', 'проверка'}
КОД = {**дочернее_назначение.приём.ЗАГРУЖЕННЫЙ_КОД,
       **дочернее_назначение.КОД, **дочернее_назначение.область_писателя.КОД}
КОД.update({Path(м.__file__).resolve(): hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
       for м in (дочернее_назначение, нативный_приём, хранение, гит, доставка_план, доставка_отчёта,
                 отложенные_назначения, нативный_приём.нативные_вызовы, нативный_приём.остановка_ребёнка)})
КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def сформировать(блок):
    хранение.поля(блок, ПОЛЯ)
    хранение.требовать(блок['схема'] == 'fum.поручение-дочернего-приёма.1', 'Неизвестное поручение приёма')
    for ключ in ('корневая_задача', 'исполнитель', 'проверка'):
        хранение.требовать(хранение.идентификатор_задачи(блок[ключ]), 'Неверный UUID поручения приёма')
    for ключ in ('база', 'исходный_коммит', 'срез', 'источник_приёмки'):
        хранение.требовать(хранение.шестнадцатеричный(блок[ключ], 40), 'Нужен полный OID поручения приёма')
    for ключ in ('назначение_sha256', 'план'):
        хранение.требовать(хранение.шестнадцатеричный(блок[ключ]), 'Нужен отпечаток поручения приёма')
    for ключ in ('слой', 'корень', 'ref', 'журнал'):
        хранение.требовать(хранение.текст(блок[ключ]), 'Нужна точная строка поручения приёма')
    хранение.требовать(re.fullmatch(r'Журнал/\d{4}-\d{2}-\d{2}_\d{2}-\d{2}-\d{2}_MSK_[^/\x00-\x1f]+/', блок['журнал']),
                       'Нужна точная новая папка Журнала')
    хранение.путь_результата(блок['журнал'].removesuffix('/'))
    return НАЧАЛО + хранение.байты(блок).decode('utf-8') + КОНЕЦ


def проверить_код(корень, база, *, дополнительный_код=None):
    """Добавочный контур задаёт доверенный вызывающий при загрузке, не входной JSON."""
    дочернее_назначение.проверить_код(корень, база)
    корень = Path(корень)
    состав = доставка_отчёта.дерево(корень, база)
    хранение.требовать(гит.гит(корень, 'rev-parse', '--show-object-format') == 'sha1', 'Нужен SHA-1 коммит базы C')
    контур = dict(КОД)
    for путь, отпечаток in (дополнительный_код or {}).items():
        хранение.требовать(путь not in контур or контур[путь] == отпечаток,
            'Противоречивые отпечатки загруженного кода')
        контур[путь] = отпечаток
    for путь, отпечаток in контур.items():
        хранение.требовать(путь.is_relative_to(корень / 'Инструменты'), 'Код приёма загружен из другого checkout')
        хранение.безопасный_путь(путь)
        данные = путь.read_bytes()
        хранение.требовать(hashlib.sha256(данные).hexdigest() == отпечаток,
                           'Код приёма изменён после загрузки')
        запись = состав.get(путь.relative_to(корень).as_posix())
        объект = hashlib.sha1(b'blob ' + str(len(данные)).encode('ascii') + b'\0' + данные).hexdigest()
        хранение.требовать(запись is not None and запись['режим'] in {'100644', '100755'}
            and запись['объект'] == объект, 'Код приёма отсутствует в коммите базы C')


def сравнимое(значение):
    return unicodedata.normalize('NFC', значение).casefold()


def проверить_деревья(корень, база, вершина, срез, журнал):
    деревья = {имя: доставка_отчёта.дерево(корень, имя) for имя in (база, вершина, срез)}
    def контур(состав):
        return {п: з for п, з in состав.items()
                if сравнимое(п).split('/', 1)[0] in {'agents.md', 'правила', 'инструменты', '.codex'}}
    хранение.требовать(контур(деревья[база]) == контур(деревья[срез]), 'Проверочный контур C/S различается')
    ключ = сравнимое(журнал.removesuffix('/'))
    for состав in (деревья[вершина], деревья[срез]):
        for путь in состав:
            иной = сравнимое(путь)
            хранение.требовать(not (иной == ключ or иной.startswith(ключ + '/') or ключ.startswith(иной + '/')),
                               'Назначенный Журнал уже существует в принятой истории')


def прочитать(корень, задача, источник, план, свидетельство, текст):
    хранение.требовать(type(текст) is str and текст.startswith(НАЧАЛО) and текст.endswith(КОНЕЦ),
                       'Нужен полный канонический текст приёма')
    блок = хранение.разобрать(текст[len(НАЧАЛО):-len(КОНЕЦ)].encode('utf-8'))
    хранение.требовать(сформировать(блок) == текст, 'Текст приёма не канонический')
    основание = дочернее_назначение.прочитать_основание(корень, задача, источник)
    корень = Path(основание['писатель']['путь'])
    привязка = дочернее_назначение.привязка(основание)
    ожидаемое = {'корневая_задача': основание['корневая_задача'], 'исполнитель': задача,
        'база': основание['база'], 'назначение_sha256': хранение.хэш(привязка), 'слой': основание['слой'],
        'корень': str(корень), 'ref': основание['писатель']['ref'], 'исходный_коммит': основание['писатель']['HEAD']}
    хранение.требовать(all(блок[к] == з for к, з in ожидаемое.items()), 'Поручение другого первоначального назначения')
    проверить_код(корень, блок['база'])
    нативный = нативный_приём.прочитать(свидетельство, блок['корневая_задача'], задача, str(корень), источник, текст)
    доставка_план.проверить_план(план)
    хранение.требовать(блок['план'] == план['идентификатор'], 'Поручение другого плана доставки')
    принятый = план['источник']
    хранение.требовать(принятый['владелец'] == блок['корневая_задача']
        and принятый['срез'] == блок['срез'] and принятый['коммит'] == блок['источник_приёмки'],
        'Подменены срез или источник приёмки')
    приёмка = доставка_план.прочитать_приёмку(корень, блок['источник_приёмки'], блок['срез'], принятый['приёмка'])
    хранение.требовать(all(принятый[к] == з for к, з in приёмка.items()), 'Вложенная приёмка отличается от Git')
    свои = [э for э in план['получатели'] if э['владелец'] == задача or э['корень'] == str(корень) or э['ref'] == блок['ref']]
    ожидаемый = {'корень': str(корень), 'владелец': задача, 'ref': блок['ref'], 'коммит': блок['исходный_коммит'],
        'дерево': гит.гит(корень, 'rev-parse', блок['исходный_коммит'] + '^{tree}')}
    хранение.требовать(len(свои) == 1 and all(свои[0][к] == з for к, з in ожидаемый.items()), 'Не совпал единственный свой получатель')
    for ключ in ('база', 'исходный_коммит', 'срез', 'источник_приёмки'):
        гит.полный_объект(корень, блок[ключ])
    хранение.требовать(блок['исходный_коммит'] != блок['срез']
        and гит.предок(корень, блок['база'], блок['исходный_коммит'])
        and гит.предок(корень, блок['исходный_коммит'], блок['срез']), 'Нужна история C → H → S с H != S')
    проверить_деревья(корень, блок['база'], блок['исходный_коммит'], блок['срез'], блок['журнал'])
    хранение.требовать(дочернее_назначение.прочитать_основание(корень, задача, источник) == основание
        and нативный_приём.прочитать(свидетельство, блок['корневая_задача'], задача, str(корень), источник, текст) == нативный,
        'Основание или нативное поручение изменилось при чтении')
    проверить_код(корень, блок['база'])
    результат = {'схема': 'fum.основание-дочернего-приёма.1', 'назначение': привязка, 'поручение': блок,
        'эпизод': хранение.хэш({'назначение_sha256': блок['назначение_sha256'], 'исполнитель': задача}),
        'срез': блок['срез'], 'дерево': принятый['дерево'], 'приёмка': приёмка, 'нативный_приём': нативный,
        'журнал': блок['журнал'], 'проверка': блок['проверка'], 'разрешение_записи': False}
    return {**результат, 'sha256': хранение.хэш(результат)}

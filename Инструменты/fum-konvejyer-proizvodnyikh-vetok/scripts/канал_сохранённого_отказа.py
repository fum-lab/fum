"""Читает только известный канал обёртки в закрытом каталоге; ничего не меняет."""
import hashlib
import os
from pathlib import Path
import stat

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

from приватные_файлы_отказа import СнимокФайлов, _метка
import приём_направления as хранение


def прочитать(описание, задача):
    хранение.поля(описание, {'путь', 'байты', 'sha256'})
    хранение.требовать(хранение.идентификатор_задачи(задача), 'Нужен UUID владельца канала')
    база = Path('/private/var/tmp/fum-soobsjheniya-' + задача)
    путь = база / 'ответ-приёма.json'
    хранение.требовать(описание['путь'] == str(путь)
        and type(описание['байты']) is int and 0 < описание['байты'] <= 1048576
        and хранение.шестнадцатеричный(описание['sha256']), 'Чужой или неограниченный канал')
    каталоги = СнимокФайлов(); каталоги._каталоги(путь, база)
    до = путь.lstat()
    # Исходная известная обёртка создавала 0644 внутри 0700. Права не меняются.
    хранение.требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1
        and до.st_uid == os.getuid() and stat.S_IMODE(до.st_mode) in {0o400, 0o600, 0o644}
        and до.st_size == описание['байты'], 'Подменён обычный канал закрытого каталога')
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK), 'rb') as файл_канала:
        хранение.требовать(_метка(os.fstat(файл_канала.fileno())) == _метка(до), 'Подменён открытый канал')
        сырой = файл_канала.read(1048577)
        хранение.требовать(len(сырой) == до.st_size and _метка(os.fstat(файл_канала.fileno())) == _метка(до),
            'Канал изменился во время чтения')
    хранение.требовать(_метка(путь.lstat()) == _метка(до)
        and hashlib.sha256(сырой).hexdigest() == описание['sha256'], 'Изменён исходный канал отказа')
    каталоги._каталоги(путь, база); каталоги.сверить()
    return сырой

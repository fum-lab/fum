def _вызов(объект, имя):
    хранение.требовать(type(объект) is dict and объект.get('инструмент') == имя
        and хранение.текст(объект.get('id')) and type(объект.get('аргументы')) is dict,
        'Нужен собственный наблюдённый MCP-вызов')
    хранение.поля(объект['источник'], {'начало', 'конец', 'sha256'})
    п = объект['источник']; хранение.поля(объект['интервал'], {'начало_мс', 'конец_мс'})
    и = объект['интервал']
    хранение.требовать(all(type(п[к]) is int for к in ('начало','конец'))
        and 0 <= п['начало'] < п['конец'] and хранение.шестнадцатеричный(п['sha256'])
        and all(type(и[к]) is int for к in ('начало_мс','конец_мс'))
        and 0 <= и['начало_мс'] <= и['конец_мс'], 'Неполные границы MCP-вызова')


def проверить(сырые, остановка, корневая, текст, send, wait, цель, *, вид, канал=None, артефакт=None, профиль=None):
    хранение.требовать(профиль is None or type(профиль) is dict, 'Нужен словарь профиля')
    начало = последнее = time.monotonic_ns()
    def отметить(имя):
        nonlocal последнее
        теперь = time.monotonic_ns()
        if профиль is not None:профиль[имя] = теперь-последнее
        последнее = теперь
    хранение.требовать(хранение.идентификатор_задачи(корневая)
        and type(текст) is str and bool(текст.strip()) and '\0' not in текст
        and вид in {'direct','saved-wrapper'}, 'Неизвестная связь нового приёма')
    _вызов(send, 'send_message_to_thread'); _вызов(wait, 'wait_threads')
    хранение.требовать(set(send['аргументы']) <= {'threadId','prompt','hostId','model','thinking'}
        and send['аргументы'].get('threadId') == цель['задача'] != корневая
        and send['аргументы'].get('prompt') == текст, 'Чужой адрес или текст send')
    цели = wait['аргументы'].get('targets')
    хранение.требовать(type(цели) is list and len(цели) == 1 and type(цели[0]) is dict
        and цели[0].get('threadId') == цель['задача'] and type(wait.get('ответ')) is dict
        and wait['ответ'].get('isError') is False, 'Нужен единственный собственный успешный postwait')
    хранение.требовать(send['источник']['конец'] <= wait['источник']['начало']
        and send['интервал']['конец_мс'] < wait['интервал']['начало_мс'], 'Postwait опередил или перекрыл send')
    получено, строки = транспорт.прочитать_рамки_входа(сырые, остановка, корневая,
        цель['задача'], цель['корень'], текст)
    отметить('транспорт')
    записи = [з[2] for з in строки]
    ход = остановка_ребёнка.подтвердить_ход(записи, цель['задача'], wait, True, корень=цель['корень'])
    старые = [з for з in строки if з[1] <= остановка['граница']]
    while старые and старые[-1][2].get('type') == 'event_msg' \
            and старые[-1][2].get('payload',{}).get('type') == 'thread_settings_applied':
        настройки = старые[-1][2]['payload']
        хранение.требовать(set(настройки) == {'type','thread_id','thread_settings'}
            and настройки['thread_id'] == цель['задача']
            and type(настройки['thread_settings']) is dict
            and настройки['thread_settings'].get('cwd') == цель['корень'],
            'Чужие или неполные настройки после прежней остановки')
        старые.pop()
    хранение.требовать(старые and старые[-1][2].get('type') == 'event_msg'
        and старые[-1][2].get('payload',{}).get('type') == 'task_complete', 'Нет прежней конечной остановки')
    прежний = старые[-1][2]['payload'].get('turn_id')
    хранение.требовать(хранение.идентификатор_задачи(прежний) and ход != прежний
        and ход == цель['ход'], 'CLI относится к прежнему или другому ходу')
    хвост = [з for з in строки if з[0] >= остановка['граница']]
    конечные = [з for з in хвост if з[2].get('type') == 'event_msg'
        and з[2].get('payload',{}).get('type') == 'task_complete']
    начала = [з for з in хвост if з[2].get('type') == 'event_msg'
        and з[2].get('payload',{}).get('type') == 'task_started']
    хранение.требовать(len(конечные) == 1 and len(начала) <= 1
        and all(з[2]['payload'].get('turn_id') == ход for з in начала)
        and all(з[2]['payload'].get('thread_id',цель['задача']) == цель['задача'] for з in [*начала,*конечные]),
        'Нет единственного нового завершённого хода')
    конец = конечные[0]
    хранение.требовать(получено['конец'] <= цель['начало'] < цель['конец'] <= конец[0]
        and all(з[1] <= цель['начало'] for з in начала), 'CLI не расположен между своим поручением и концом')
    отметить('сопоставление_ходов')
    if вид == 'direct':
        хранение.требовать(канал is None and артефакт is None, 'Приватный канал другого вида отказа')
        отказ = прямой.проверить(сырые, цель)
    else:
        отказ = сохранённый.проверить(сырые, цель, канал, артефакт)
    и = отказ['интервал']
    хранение.требовать(send['интервал']['начало_мс'] <= и['начало_мс'] <= и['конец_мс']
        <= wait['интервал']['конец_мс'], 'Runtime отказа вышел за свой send/postwait')
    отметить('CLI')
    if профиль is not None:профиль['всего'] = time.monotonic_ns()-начало
    описать = lambda в: {к: в[к] for к in ('id','источник','интервал')}
    return {'схема':'fum.связанный-отказ-после-остановки.1', 'задача':цель['задача'],
        'прежний_ход':прежний, 'ход':ход, 'получение':получено, 'отправка':описать(send),
        'ожидание':описать(wait), 'конец':{'начало':конец[0],'конец':конец[1],
            'sha256':hashlib.sha256(сырые[конец[0]:конец[1]]).hexdigest()},
        'источник':{'граница':len(сырые),'sha256':hashlib.sha256(сырые).hexdigest()},
        'отказ':отказ, 'повтор_эффекта_разрешён':False,
        'граница':'Чистая связь переданных свидетельств; полный ROOT, FS/Git и терминал проверяются отдельно'}

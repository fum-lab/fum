"""Долговечная установка J после merge; заполненный отчёт повтором не заменяется."""
import hashlib
import os
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import эпизод_приёма as эпизод
import план_журнала_приёма as план
import область_журнала_приёма as область
import файл_журнала_приёма
import слияние_приёма
import обратная_доставка
import доставка_состояние
import отчёты_о_запусках_проверок
import захват_вывода

хранение = эпизод.хранение
КОД = {Path(м.__file__).resolve(): м.КОД_ПРИ_ЗАГРУЗКЕ
    for м in (эпизод, план, область, файл_журнала_приёма, слияние_приёма, обратная_доставка,
        доставка_состояние, план.каркас, эпизод.файлы, эпизод.файлы._КЛАССИФИКАТОР,
        отчёты_о_запусках_проверок, захват_вывода)}
КОД[Path(__file__).resolve()] = КОД_ПРИ_ЗАГРУЗКЕ
КОД.update({п.resolve(): hashlib.sha256(п.read_bytes()).hexdigest() for п in (
    план.каркас.КАТАЛОГ_ШАБЛОНОВ / 'запрос.md.шаблон',
    план.каркас.КАТАЛОГ_ШАБЛОНОВ / 'отчёт.md.шаблон')})


class ЖурналПриёма:
    """Внутренний получатель проверенного СлияниеПриёма; не самостоятельный допуск."""
    def __init__(сам, слияние):
        сам.слияние = слияние
        сам.основание = слияние.основание
        сам.доставка = слияние._доставка
        сам.путь = эпизод.путь_эпизода(сам.основание).with_suffix('.журнал.json')

    def _граница(сам, имя):
        """Наблюдаемая граница для проверки прерываний без отката чужих файлов."""

    def _проверить_код(сам):
        with сам.слияние._метка('проверка загруженного кода и шаблонов'):
            план.приём_интеграции.проверить_код(сам.доставка.корень,
                сам.основание['поручение']['база'], дополнительный_код=КОД)

    def _сохранить(сам, данные):
        хранение.установить(сам.путь, хранение.байты({'данные': данные, 'sha256': хранение.хэш(данные)}))

    def _прочитать(сам):
        хранение.безопасный_путь(сам.путь)
        if not сам.путь.exists():
            return None
        конверт = эпизод.прочитать_файл(сам.путь)
        хранение.поля(конверт, {'данные', 'sha256'})
        данные = конверт['данные']
        хранение.требовать(конверт['sha256'] == хранение.хэш(данные), 'Повреждено намерение Журнала')
        хранение.поля(данные, {'схема', 'план', 'состояние'})
        хранение.требовать(данные['схема'] == 'fum.установка-журнала-приёма.1'
            and данные['состояние'] in {'устанавливается', 'установлено'}, 'Неизвестная стадия Журнала')
        план.проверить(данные['план'], сам.основание)
        return данные

    def установить(сам):
        # До инфраструктуры замка и при каждом восстановлении.
        сам._проверить_код()
        with сам.слияние._замок(), сам.слияние._метка('установка или чтение нового Журнала'):
            хранение.требовать(эпизод.прочитать(сам.основание) is not None, 'Нет намерения приёма')
            данные = сам._прочитать()
            if данные is None:
                # Полный прежний допуск годится только до появления J.
                квитанция = сам.доставка.состояние()
                область.проверить_путь(сам.доставка.корень, сам.основание['журнал'])
                хранение.требовать(not os.path.lexists(сам.доставка.корень / сам.основание['журнал']),
                    'Новый Журнал уже занят без сохранённого намерения')
                данные = {'схема': 'fum.установка-журнала-приёма.1',
                    'план': план.подготовить(сам.основание), 'состояние': 'устанавливается'}
                сам._проверить_код()
            установлено = данные['состояние'] == 'установлено'
            описание = данные['план']
            допустимые = set(описание['будущие_пути'] if установлено else
                [з[ключ] for з in описание['файлы'] for ключ in ('путь', 'временный')])
            with сам.доставка.хранилище.замок() as хранилище:
                квитанция = хранилище.прочитать()
                область.слияние(сам.доставка, сам.основание, квитанция, допустимые, установлено)
            область.файлы(сам.доставка.корень, описание, установлено)
            if установлено:
                return данные
            # Даже перед восстановлением проверена вся пара: чужая первая часть
            # не разрешает создать вторую. Существующие точные байты не заменяются.
            if not сам.путь.exists():
                сам._сохранить(данные)
                сам._граница('намерение')
            папка = сам.доставка.корень / описание['журнал']
            хранение.создать_каталоги(папка, сам.доставка.корень)
            сам._граница('каталоги')
            for запись in описание['файлы']:
                путь = сам.доставка.корень / запись['путь']
                if not путь.exists():
                    файл_журнала_приёма.установить(путь, сам.доставка.корень / запись['временный'],
                        запись['текст'].encode('utf-8'), запись['режим'])
                # Повтор закрепляет уже совпавшие файлы после fsync-отказа.
                with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
                    os.fsync(поток.fileno())
                хранение.синхронизировать_каталог(путь.parent)
                сам._граница(путь.name)
            область.файлы(сам.доставка.корень, описание, False)
            сам._граница('пара')
            данные['состояние'] = 'установлено'
            сам._сохранить(данные)
            return данные

"""Закрытый адаптер J → R: импорт S неизменен, своей записью остаётся только J."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import эпизод_приёма as эпизод
import приём_интеграции
import слияние_приёма
import журнал_приёма
import план_журнала_приёма as план
import область_журнала_приёма as область
import доставка_гит as гит
import доставка_отчёта

хранение = эпизод.хранение


def адрес(параметры):
    """Только неизменяемая структура и адрес квитанции; допустимо после R."""
    хранение.требовать(параметры.get('схема') == 'fum.создание-коммита.4'
        and параметры.get('режим') == 'дочерний-приём', 'Нужен режим дочернего приёма')
    вход = параметры['приём']
    хранение.поля(вход, {'основание', 'план', 'реестр', 'свидетельство'})
    основание = вход['основание']; эпизод.проверить_основание(основание)
    блок = основание['поручение']
    ожидаемое = {'задача': блок['корневая_задача'], 'исполнитель': блок['исполнитель'],
        'назначение_sha256': блок['назначение_sha256'], 'основание_sha256': основание['sha256'],
        'корень': блок['корень'], 'ветка': блок['ref'], 'исходный_коммит': блок['исходный_коммит'],
        'родители': [блок['исходный_коммит'], блок['срез']], 'источники': [],
        'запрос': основание['журнал'] + 'запрос.md',
        'история_модели': основание['журнал'] + 'материалы/история-модели.json',
        'разрешённые_цели': план.будущие_пути(основание),
        'квитанция': str(эпизод.путь_эпизода(основание).with_suffix('.коммит.json'))}
    хранение.требовать(all(параметры.get(к) == з for к, з in ожидаемое.items()),
        'Изменена привязка коммита приёма, четыре цели J или каноническая квитанция')
    приватные = [Path(параметры[к]) for к in ('источник_модели', 'кэш_модели', 'сообщение', 'подготовка', 'квитанция')]
    хранение.требовать(len(set(приватные)) == len(приватные), 'Приватные пути приёма совпали')
    for путь in [*приватные, Path(вход['реестр'])]:
        хранение.требовать(путь.is_absolute() and путь == путь.resolve()
            and not any((п / '.git').exists() for п in путь.parents), 'Приватный путь приёма находится в Git')
        хранение.безопасный_путь(путь)
    return основание


def проверить(параметры, *, окончательно=False):
    основание = адрес(параметры); вход = параметры['приём']; корень = Path(параметры['корень'])
    def перечитать():
        return приём_интеграции.прочитать(корень, параметры['исполнитель'], параметры['источник_модели'],
            вход['план'], вход['свидетельство'], основание['нативный_приём']['текст'])
    хранение.требовать(перечитать() == основание, 'Сдвинулось нативное основание приёма')
    хранение.требовать(эпизод.прочитать(основание) is not None, 'Нет сохранённого эпизода приёма')
    слияние = слияние_приёма.СлияниеПриёма(основание, вход['план'], вход['реестр'], перечитать)
    журнал = журнал_приёма.ЖурналПриёма(слияние)
    журнал._проверить_код()
    import создание_коммита as создатель
    import связность_приёма
    контур = {Path(м.__file__).resolve(): м.КОД_ПРИ_ЗАГРУЗКЕ
        for м in (создатель, создатель.готовность, связность_приёма)}
    контур[Path(__file__).resolve()] = КОД_ПРИ_ЗАГРУЗКЕ
    приём_интеграции.проверить_код(корень, основание['поручение']['база'], дополнительный_код=контур)
    данные = журнал._прочитать()
    хранение.требовать(данные is not None and данные['состояние'] == 'установлено', 'Журнал приёма не установлен')
    описание = данные['план']
    область.файлы(корень, описание, True)
    with слияние._доставка.хранилище.замок() as хранилище:
        область.слияние(слияние._доставка, основание, хранилище.прочитать(), set(параметры['разрешённые_цели']), True)
    if окончательно:
        импорт = доставка_отчёта.дерево(корень, основание['срез'])
        индекс = доставка_отчёта.дерево(корень, гит.гит(корень, 'write-tree'))
        хранение.требовать(set(индекс) - set(импорт) == set(параметры['разрешённые_цели']),
            'В индексе отсутствует один из четырёх конечных файлов J')
    return основание


def состав(параметры):
    основание = проверить(параметры, окончательно=True)
    корень = Path(параметры['корень'])
    return {'основание': основание['sha256'], 'индекс': гит.гит(корень, 'write-tree'),
        'свои': {п: hashlib.sha256((корень / п).read_bytes()).hexdigest() for п in параметры['разрешённые_цели']}}


def первичные(параметры):
    основание = проверить(параметры)
    нативный = основание['нативный_приём']
    return [{'задача': параметры['задача'], 'исполнитель': параметры['исполнитель'],
        'экземпляр': хранение.хэш(нативный), 'происхождение': 'поручение-приёма-корня',
        'позиция': нативный['получение'], 'текст': нативный['текст']}]


def проверки(параметры, необходимые, записи):
    основание = адрес(параметры)
    хранение.требовать(необходимые == [основание['проверка']] and len(записи) == 1,
        'Приём требует единственную назначенную проверку')
    путь, запись, _ = записи[0]
    хранение.требовать(Path(путь) == Path(параметры['корень']) / параметры['разрешённые_цели'][3]
        and запись['порядок'] == 1 and запись['профиль_проверки']['класс'] == 'адресная'
        and запись['план'] is None and запись['наблюдения'] == [] and запись['переход_схемы'] is None,
        'Изменена точная адресная запись проверки приёма')


def связность(параметры, сообщение, валидатор):
    from связность_приёма import проверить
    return проверить(параметры, сообщение, валидатор)

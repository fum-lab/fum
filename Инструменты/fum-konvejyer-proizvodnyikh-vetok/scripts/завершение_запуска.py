"""Конечный переход своего неудачного пилота из recovery без переноса владельца."""
import copy
import hashlib
from pathlib import Path

import приём_направления as хранение
from отложенные_назначения import извлечь_ответ
import нативные_вызовы
import остановка_ребёнка
import терминал_запуска

КОД = {Path(м.__file__).resolve(): hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
       for м in (нативные_вызовы, остановка_ребёнка, терминал_запуска)}
КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def _живые_ветки(исполнитель, вход, план):
    координатор = исполнитель.хранилище._наблюдать_владельца()
    хранение.требовать(координатор == вход["координатор"], "Изменён текущий координатор")
    прежний = план["координатор"]
    хранение.требовать(хранение.гит(исполнитель.корень, "show-ref", "--hash", "--verify", прежний["ref"]).strip() == прежний["HEAD"], "Исходный C сдвинулся")
    деревья = хранение.гит(исполнитель.корень, "worktree", "list", "--porcelain", "-z")
    хранение.требовать("branch " + прежний["ref"] not in деревья.split("\0"), "Прежний ref занят деревом")
    ветки = хранение.гит(исполнитель.корень, "for-each-ref", "--format=%(refname)", "refs/heads/").splitlines()
    for слой in план["описание"]["слои"]:
        хранение.требовать(not any(слой["ветка"].casefold() == в.casefold() for в in ветки), "Назначенная ветка уже создана")
    хранение.гит(исполнитель.корень, "merge-base", "--is-ancestor", прежний["HEAD"], координатор["HEAD"])
    return координатор


def _план(исполнитель, вход, состояние):
    хранение.поля(вход, {"схема", "запуск", "план_sha256", "координатор", "источник", "слои", "свидетельство_координатора"})
    хранение.требовать(вход["схема"] == "fum.завершение-неудачного-запуска.1", "Неизвестный переход завершения")
    запись = исполнитель._прочитать(состояние, вход["запуск"])
    план = запись["план"]
    хранение.требовать(план["sha256"] == вход["план_sha256"] and запись["смысл"]["схема"] in {"fum.запуск-двух-слоёв.2", "fum.запуск-двух-слоёв.3", "fum.запуск-двух-слоёв.4"}
                       and all(н is None for н in запись["наблюдения"].values()), "Нужен ненаблюдённый запуск v2, v3 либо v4")
    попытки = {слой: состояние["попытки"].get(ключ) for слой, ключ in план["попытки"].items()}
    исторический = хранение.хэш({"запись": запись, "попытки": попытки})
    прежний = терминал_запуска.прочитать(состояние, вход["запуск"])
    if прежний is not None:
        хранение.требовать(прежний["вход_sha256"] == хранение.хэш(вход)
                           and прежний["история_sha256"] == исторический, "Повтор изменил свидетельство или историю")
        return copy.deepcopy(прежний)
    координатор = _живые_ветки(исполнитель, вход, план)
    прежний_владелец = план["координатор"]
    хранение.требовать(состояние["писатели"].get(str(исполнитель.корень))
                       == {"задача": исполнитель.задача, "ref": прежний_владелец["ref"]}
                       and координатор["ref"] != прежний_владелец["ref"], "Нет того же исторического владельца в recovery")
    хранение.требовать(not any(в["ref"] == координатор["ref"] for к, в in состояние["писатели"].items() if к != str(исполнитель.корень)), "Recovery ref принадлежит другому писателю")
    база = прежний_владелец["HEAD"]
    исполнитель._инструменты(координатор["HEAD"])
    for путь, хэш in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == хэш, "Код завершения изменён после загрузки")
    хранение.требовать(type(вход["слои"]) is dict and set(вход["слои"]) == set(попытки), "Неполный состав слоёв")
    хранение.требовать(вход["свидетельство_координатора"] == {"задача": исполнитель.задача, "единственный_координатор": True,
                       "нет_незаписанных_или_выполняющихся_вызовов": True, "ребёнок_не_возобновляется": True},
                       "Нет явной кооперативной аттестации координатора")
    дети = []
    for слой, завершение in вход["слои"].items():
        хранение.требовать(type(попытки[слой]) is dict and type(завершение) is dict, "Нет попытки слоя")
        остановлен = завершение.get("вид") == "остановлен-до-записи"
        хранение.поля(завершение, {"вид", "попытка"} | ({"задача", "корень", "источник", "ожидание"} if остановлен else set()))
        хранение.требовать(завершение["вид"] in {"остановлен-до-записи", "не-вызван"}
                           and завершение["попытка"] == попытки[слой]["попытка"]
                           and попытки[слой]["аргументы"] == план["аргументы"][слой]
                           and попытки[слой]["база"] == база, "Изменена попытка слоя")
        if остановлен:
            дети.append(завершение["задача"])
    хранение.требовать(len(дети) == 1 and len(попытки) == 2, "Переход рассчитан на одного остановленного ребёнка и один неиспользованный допуск")
    нативный = нативные_вызовы.прочитать(вход["источник"], исполнитель.задача,
        аргументы=[п["аргументы"] for п in попытки.values()], ожидания=дети)
    хранение.требовать(нативный["источник"]["начало"] == нативный["начальная_граница"], "Нужна полная история после session_meta")
    хранение.требовать(not нативный["возобновления"], "Пилот содержит записанное возобновление ребёнка")
    результаты = {}
    for имя, завершение in вход["слои"].items():
        попытка = попытки[имя]
        вызовы = [в for в in нативный["вызовы"] if в["аргументы"] == попытка["аргументы"]]
        if завершение["вид"] == "не-вызван":
            хранение.требовать(not вызовы and попытка["ответ"] is None, "Есть вызов либо ответ неиспользованного допуска")
            результаты[имя] = {"вид": "допуск-отозван", "попытка": попытка["попытка"], "записанных_вызовов": 0}
            continue
        хранение.требовать(len(вызовы) == 1 and извлечь_ответ(вызовы[0]["ответ"]) == попытка["ответ"], "Нет единственного точного вызова и сохранённого ответа")
        ответ = попытка["ответ"]
        хранение.требовать(not ответ.get("противоречивые_идентификаторы") and ответ.get("threadId") in (None, завершение["задача"]), "Ответ противоречит задаче")
        ожидания = нативный["ожидания"]
        хранение.требовать(ожидания and ожидания[-1]["id"] == завершение["ожидание"]
                           and ожидания[-1]["источник"]["начало"] >= вызовы[0]["источник"]["конец"], "Нужно последнее ожидание после запуска")
        ожидание = ожидания[-1]
        результаты[имя] = {"вид": завершение["вид"], "попытка": попытка["попытка"], "вызов": вызовы[0]["источник"],
            "остановка": остановка_ребёнка.проверить(исполнитель, завершение, база, попытка["аргументы"]["prompt"], ожидание)}
    квитанция = {"схема": терминал_запуска.СХЕМА, "запуск": вход["запуск"], "план_sha256": план["sha256"],
                 "вход_sha256": хранение.хэш(вход), "история_sha256": исторический, "координатор": координатор,
                 "слои": результаты, "источник": нативный["источник"],
                 "свидетельство_координатора": вход["свидетельство_координатора"],
                 "отсутствие_незаписанного_вызова_доказано": False}
    return {**квитанция, "sha256": хранение.хэш(квитанция)}


def предпросмотр(исполнитель, вход):
    return _план(исполнитель, вход, исполнитель.хранилище.прочитать())


def завершить(исполнитель, вход, ожидаемый_sha256):
    with исполнитель.хранилище.изменить() as состояние:
        результат = _план(исполнитель, вход, состояние)
        хранение.требовать(результат["sha256"] == ожидаемый_sha256, "Изменён просмотренный переход")
        ключ = терминал_запуска.ключ(вход["запуск"])
        if ключ not in состояние["приёмы"]:
            план = исполнитель._прочитать(состояние, вход["запуск"])["план"]
            _живые_ветки(исполнитель, вход, план)
            for слой in вход["слои"].values():
                if слой["вид"] == "остановлен-до-записи":
                    остановка_ребёнка.проверить_дерево(исполнитель, слой, план["координатор"]["HEAD"])
                    остановка_ребёнка.снимок(слой["источник"])
            состояние["приёмы"][ключ] = результат
        return copy.deepcopy(результат)

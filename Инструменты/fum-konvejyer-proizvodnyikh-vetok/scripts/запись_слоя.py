"""Установка собственного конечного плана после повторной проверки назначения."""
import hashlib
import os
from pathlib import Path, PurePosixPath
import subprocess
import sys

import дочернее_назначение
import приём_направления as хранение
import снимок_области

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-struktura-papok-zaprosov/scripts'))
import request_folder_layout as каркас

КОД = {Path(имя).resolve(): hashlib.sha256(Path(имя).read_bytes()).hexdigest()
       for имя in (__file__, каркас.__file__)}


def проверить_код():
    for путь, отпечаток in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == отпечаток,
                           'Код установки изменён после загрузки')


def проверить_коллизии(пути):
    """Проверить будущие файлы и написание всех ещё отсутствующих каталогов."""
    имена, файлы = {}, set()
    for путь in пути:
        ключ = каркас._portable_key(путь)
        хранение.требовать(ключ not in файлы, 'Переносимая коллизия целей: ' + str(путь))
        файлы.add(ключ)
        for часть in (путь, *путь.parents):
            if часть == PurePosixPath('.'):
                continue
            ключ = каркас._portable_key(часть)
            хранение.требовать(ключ not in имена or имена[ключ] == часть,
                               'Переносимая коллизия пути: ' + str(часть))
            имена[ключ] = часть
    хранение.требовать(not any(каркас._portable_key(предок) in файлы
                               for путь in пути for предок in путь.parents), 'Цели плана пересекаются')


def сверить_входы(корень, назначение, входы):
    хранение.требовать(isinstance(входы, dict), 'Нужен конечный снимок входов')
    for имя, состояние in входы.items():
        хранение.требовать(isinstance(имя, str) and any(имя.startswith(п) for п in назначение['каталоги']),
                           'Вход вне области писателя')
        путь = снимок_области.охват.точный_путь(корень, имя)
        хранение.требовать(снимок_области.охват.состояние_пути(путь) == состояние,
                           'Прежние байты входа сдвинулись: ' + имя)


def проверить_игнорирование(корень, цели):
    if not цели:
        return
    среда = {к: з for к, з in os.environ.items() if not к.startswith('GIT_')}
    среда['GIT_OPTIONAL_LOCKS'] = '0'
    проверка = subprocess.run(['git', '-C', str(корень), 'check-ignore', '--no-index', '-z', '--stdin'],
        env=среда, input=b''.join(имя.encode() + b'\0' for имя in sorted(цели)), capture_output=True, timeout=30)
    хранение.требовать(проверка.returncode == 1 and not проверка.stdout, 'План содержит игнорируемую цель либо Git отказал')


def установить(корень, задача, источник, файлы, назначение_sha256, *, ожидаемые=None, входы=None):
    """Откат обычной ошибки установки; прерывание процесса и крах ОС не атомарны."""
    проверить_код()
    назначение = дочернее_назначение.прочитать(корень, задача, источник)
    хранение.требовать(назначение['sha256'] == назначение_sha256, 'План устарел: назначение сдвинулось')
    корень = Path(корень)
    входы = {} if входы is None else входы
    сверить_входы(корень, назначение, входы)
    хранение.требовать(isinstance(файлы, (list, tuple)), 'Нужен конечный план файлов')
    цели, состояния = set(), {}
    for файл in файлы:
        хранение.требовать(isinstance(файл, каркас.PreparedFile) and isinstance(файл.path, PurePosixPath)
                           and isinstance(файл.data, bytes) and файл.mode in (0o644, 0o755), 'Неверный файл плана')
        имя = файл.path.as_posix()
        хранение.требовать(имя not in цели and any(имя.startswith(п) for п in назначение['каталоги']),
                           'Повтор цели либо путь вне области писателя: ' + имя)
        хранение.требовать(not any(ord(знак) < 32 for знак in имя), 'Управляющий символ в цели')
        путь = снимок_области.охват.точный_путь(корень, имя)
        for предок in путь.parents:
            if предок == корень:
                break
            хранение.требовать(not предок.exists() or предок.is_dir(), 'Родитель цели не является каталогом')
        состояние = снимок_области.охват.состояние_пути(путь)
        хранение.требовать(состояние['тип'] in {'файл', 'отсутствует'}, 'Цель не является обычным файлом')
        цели.add(имя)
        состояния[имя] = состояние
    пути = [PurePosixPath(имя) for имя in цели]
    проверить_коллизии(пути)
    if ожидаемые is not None:
        хранение.требовать(состояния == ожидаемые, 'Прежние байты целей сдвинулись')
    проверить_игнорирование(корень, цели)
    хранение.требовать(дочернее_назначение.прочитать(корень, задача, источник) == назначение,
                       'Назначение сдвинулось перед установкой')
    for имя, состояние in состояния.items():
        путь = снимок_области.охват.точный_путь(корень, имя)
        хранение.требовать(снимок_области.охват.состояние_пути(путь) == состояние,
                           'Цель сдвинулась перед установкой')
    сверить_входы(корень, назначение, входы)
    проверить_код()
    каркас._apply_prepared_transaction(корень, файлы)
    после = дочернее_назначение.прочитать(корень, задача, источник)
    return {'схема': 'fum.установка-файлов-слоя.1', 'файлы': sorted(цели),
            'до_sha256': назначение_sha256, 'после_sha256': после['sha256']}

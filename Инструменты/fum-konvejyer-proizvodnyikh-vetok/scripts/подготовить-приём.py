"""Опубликовать конверт, дождаться его и выполнить конечный приём своим владельцем."""
import argparse
import json
from pathlib import Path
import time

import конверт_приёма as конверт
import приватный_вход_приёма as вход
import нативное_поручение_приёма


def главная(аргументы=None):
    парсер = argparse.ArgumentParser(description=__doc__)
    команды = парсер.add_subparsers(dest='фаза', required=True)
    публикация = команды.add_parser('опубликовать')
    публикация.add_argument('--вход', required=True, type=Path)
    for имя in ('ожидать', 'принять', 'подготовить', 'готово', 'создать'):
        команда = команды.add_parser(имя)
        команда.add_argument('--поручение', type=Path)
        команда.add_argument('--исходник', type=Path, required=имя == 'принять')
        if имя == 'ожидать':
            команда.add_argument('--предел-секунд', type=float, default=30)
        elif имя == 'готово':
            команда.add_argument('--предел-секунд', type=int, default=600)
    п = парсер.parse_args(аргументы)
    начало = time.monotonic_ns()
    try:
        if п.фаза == 'опубликовать':
            данные = конверт.хранение.разобрать(вход.коммит.прочитать(п.вход, приватный=True))
            конверт.хранение.поля(данные, {'текст', 'план', 'владельцы', 'свидетельство', 'коммит'})
            пакет = конверт.опубликовать(**данные)
            результат = {'состояние': 'опубликовано', 'конверт_sha256': пакет['sha256'],
                'адрес': str(конверт.адрес(данные['текст']))}
        else:
            конверт.хранение.требовать(п.поручение is not None or п.исходник is not None,
                'Нужен нативный источник либо сохранённое поручение')
            текст = (вход.коммит.прочитать(п.поручение, приватный=True).decode('utf-8')
                if п.поручение is not None else нативное_поручение_приёма.прочитать(п.исходник))
            if п.фаза == 'ожидать':
                пакет = конверт.ожидать(текст, п.предел_секунд)
                результат = {'состояние': 'готово' if пакет is not None else 'ожидается-конверт',
                    'разрешение_записи': False}
            elif п.фаза == 'принять':
                результат = вход.подготовить_вход(текст, п.исходник)
            else:
                результат = вход.выполнить_фазу(текст, п.фаза, getattr(п, 'предел_секунд', 600))
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as ошибка:
        print(json.dumps({'схема': 'fum.отказ-обнаружения-приёма.1', 'ошибка': str(ошибка),
            'повтор_эффекта_разрешён': False, 'длительность_наносекунды': time.monotonic_ns() - начало}, ensure_ascii=False))
        return 2
    print(json.dumps({'результат': результат, 'длительность_наносекунды': time.monotonic_ns() - начало}, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(главная())

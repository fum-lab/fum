"""Только файловая/Git-подготовка терминала; native и допуск .9 проверяются отдельно."""
import hashlib
import os
from pathlib import Path
import time

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

import конверт_приёма as конверт
import эпизод_приёма as эпизод
import вход_приёма
import доставка_гит as гит
import доставка_план as план
import историческая_квитанция_отказа as чистый
from приватные_файлы_отказа import СнимокФайлов, _абсолютный

хранение = эпизод.хранение


def _равно(левое, правое, причина):
    хранение.требовать(хранение.байты(левое) == хранение.байты(правое), причина)


def _отсутствуют(пути):
    for путь in пути:
        хранение.безопасный_путь(путь.parent, каталог=True)
        хранение.требовать(not os.path.lexists(путь), 'Появился поздний результат приёма')


def _git(блок, пакет):
    корень = Path(блок['корень'])
    текущий = гит.снимок(корень, блок['исполнитель'], блок['ref'], пакет['план'].get('назначение'))
    свои = [п for п in пакет['план']['получатели'] if п['корень'] == блок['корень']]
    _равно(текущий, {к: свои[0][к] for к in ('корень', 'владелец', 'ref', 'коммит', 'дерево')},
        'Получатель изменился после H')
    хранение.требовать(not гит.служебные_состояния(корень), 'Есть незавершённая Git-операция')
    for имя in ('MERGE_HEAD', 'CHERRY_PICK_HEAD', 'REVERT_HEAD', 'rebase-merge', 'rebase-apply',
            'sequencer', 'BISECT_START', 'index.lock', 'MERGE_AUTOSTASH'):
        путь = Path(гит.гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', имя))
        хранение.требовать(not os.path.lexists(путь), 'Есть служебный Git-путь, включая ссылку')
    гит.поддержанное_дерево(корень, блок['срез']); гит.чисто(корень)
    хранение.требовать(блок['исходный_коммит'] != блок['срез']
        and гит.предок(корень, блок['база'], блок['исходный_коммит'])
        and гит.предок(корень, блок['исходный_коммит'], блок['срез']), 'Нужна цепочка C → H → S')
    return текущий, гит.защищённые_файлы(корень)


def прочитать(описание, текст, источник, *, профиль=None):
    хранение.требовать(профиль is None or type(профиль) is dict, 'Нужен словарь профиля')
    начало = последнее = time.monotonic_ns()
    def отметить(имя):
        nonlocal последнее
        теперь = time.monotonic_ns()
        if профиль is not None: профиль[имя] = теперь - последнее
        последнее = теперь
    хранение.поля(описание, {'конверт', 'намерение_sha256', 'доставка_sha256'})
    хранение.поля(описание['конверт'], {'путь', 'sha256'})
    _абсолютный(источник)
    путь_конверта = _абсолютный(описание['конверт']['путь'])
    хранение.требовать(all(хранение.шестнадцатеричный(з) for з in (
        описание['конверт']['sha256'], описание['намерение_sha256'], описание['доставка_sha256'])),
        'Нужны три точных SHA исходных файлов')
    блок = конверт.разобрать_текст(текст)
    хранение.требовать(путь_конверта == конверт.адрес(текст) / 'конверт.json',
        'Конверт не относится к поручению')
    файлы = СнимокФайлов()
    пакет = файлы.прочитать('конверт', путь_конверта, конверт.КОРЕНЬ_СОСТОЯНИЯ)
    _равно(конверт.проверить(пакет, текст), блок, 'Подменено поручение конверта')
    готово = файлы.прочитать('готово', путь_конверта.with_name('готово.json'), конверт.КОРЕНЬ_СОСТОЯНИЯ)
    _равно(готово, {'схема': 'fum.готовый-конверт-приёма.1', 'sha256': хранение.хэш(пакет)},
        'Подменена готовность конверта')
    файлы.состав(путь_конверта.parent, {'конверт.json', 'готово.json'})
    ключ = хранение.хэш({к: блок[к] for к in ('назначение_sha256', 'исполнитель')})
    путь = эпизод._путь_ключа(блок['исполнитель'], ключ)
    намерение = файлы.прочитать('намерение', путь, эпизод.КОРЕНЬ_СОСТОЯНИЯ)
    хранение.поля(намерение, {'данные', 'sha256'})
    хранение.требовать(намерение['sha256'] == хранение.хэш(намерение['данные']), 'Подменён SHA намерения')
    основание = намерение['данные']['основание']
    эпизод.проверить_основание(основание)
    _равно(основание['поручение'], блок, 'Намерение другого поручения')
    хранение.требовать(эпизод.путь_эпизода(основание) == путь, 'Намерение другого эпизода')
    _равно(намерение['данные'], {'схема': 'fum.намерение-дочернего-приёма.1',
        'эпизод': ключ, 'основание': основание, 'разрешение_записи': False}, 'Подменено намерение')
    метка = файлы.прочитать('начато', путь.with_suffix('.начато.json'), эпизод.КОРЕНЬ_СОСТОЯНИЯ)
    _равно(метка, {'схема': 'fum.начатый-эпизод-приёма.1', 'эпизод': ключ,
        'основание_sha256': основание['sha256']}, 'Подменена метка намерения')
    доставка = путь.with_suffix('.доставка')
    получатель = файлы.прочитать('получатель', доставка / 'получатель.json', эпизод.КОРЕНЬ_СОСТОЯНИЯ)
    активная = файлы.прочитать('активная', доставка / 'активная.json', эпизод.КОРЕНЬ_СОСТОЯНИЯ)
    _равно(получатель, {'корень': блок['корень'], 'начато': True}, 'Другая legacy-привязка получателя')
    _равно(активная, {'идентификатор': блок['план']}, 'Другой активный legacy-план')
    имя = 'квитанция-' + блок['план'] + '.json'
    сырые = файлы.прочитать('доставка', доставка / имя, эпизод.КОРЕНЬ_СОСТОЯНИЯ, json=False)
    имена = {'получатель.json', 'активная.json', имя}
    if os.path.lexists(доставка / 'замок'):
        файлы.прочитать('файл-замка', доставка / 'замок', эпизод.КОРЕНЬ_СОСТОЯНИЯ, json=False, предел=32768)
        имена.add('замок')  # Его наличие не доказывает свободы замка; замок не захватывается.
    файлы.состав(доставка, имена)
    локальный = конверт.адрес(текст, получатель=True)
    хранение.требовать(источник == str(локальный / 'нативный/источник.jsonl'),
        'Источник сохранённого входа другого приватного пакета')
    владельцы = файлы.прочитать('владельцы', локальный / 'владельцы.json', конверт.КОРЕНЬ_СОСТОЯНИЯ)
    _равно(владельцы, пакет['владельцы'], 'Подменён приватный реестр владельцев')
    данные = {'схема': 'fum.вход-дочернего-приёма.1', 'источник': источник, 'текст': текст,
        'план': пакет['план'], 'свидетельство': пакет['свидетельство'],
        'реестр': str(локальный / 'владельцы.json'), 'коммит': пакет['коммит']}
    оригинальный_вход = файлы.прочитать('вход', локальный / 'вход.json', конверт.КОРЕНЬ_СОСТОЯНИЯ)
    _равно(оригинальный_вход, данные, 'Изменён первоначальный приватный вход')
    параметры = вход_приёма.параметры(данные, основание)
    вход = файлы.прочитать('вход-коммита', путь.with_suffix('.вход-коммита.json'), эпизод.КОРЕНЬ_СОСТОЯНИЯ)
    _равно(вход, параметры, 'Подменён сохранённый вход-коммита')
    поздние = [Path(параметры[к]) for к in ('подготовка', 'квитанция')]
    поздние += [путь.with_suffix('.журнал.json'), Path(блок['корень']) / блок['журнал']]
    _отсутствуют(поздние)
    отметить('первичные_файлы')
    до, защищённые = _git(блок, пакет)
    приёмка = план.прочитать_приёмку(Path(блок['корень']), блок['источник_приёмки'],
        блок['срез'], пакет['план']['источник']['приёмка'])
    _равно(приёмка, основание['приёмка'], 'Основание не совпало с неизменяемой приёмкой Git')
    _равно({к: пакет['план']['источник'][к] for к in ('дерево', 'решение', 'полная_приёмка', 'версия')},
        приёмка, 'План не совпал с неизменяемой приёмкой Git')
    итог = чистый.проверить(сырые, основание, пакет, защищённые)
    отметить('Git_и_приёмка')
    хэши = файлы.сверить()
    _равно({к: хэши[к] for к in ('конверт', 'намерение', 'доставка')},
        {'конверт': описание['конверт']['sha256'], 'намерение': описание['намерение_sha256'],
            'доставка': описание['доставка_sha256']}, 'Исходные файлы не совпали с точными SHA')
    _отсутствуют(поздние)
    отметить('повтор_файлов')
    после, новые = _git(блок, пакет)
    _равно((после, новые), (до, защищённые), 'Git или защищённые данные изменились перед возвратом')
    файлы.сверить(); _отсутствуют(поздние)
    отметить('заключительная_сверка')
    if профиль is not None: профиль['всего'] = time.monotonic_ns() - начало
    return {'схема': 'fum.файловая-подготовка-исторического-отказа.1', 'квитанция': итог,
        'git': после, 'файлы_sha256': хэши, 'повтор_эффекта_разрешён': False,
        'нативный_допуск': 'не проверен этим слоем'}

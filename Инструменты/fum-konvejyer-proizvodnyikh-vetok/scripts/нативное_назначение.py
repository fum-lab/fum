"""Извлечение назначения только из первого нативного транспорта create_thread."""

import приём_направления as хранение
import постановка_задачи as постановка
import поручение_слоя


def прочитать(источник):
    поручение = постановка.прочитать_нативное_поручение(источник, кодирование="xml-v1")
    отправитель, текст, граница = (поручение[ключ] for ключ in ("отправитель", "текст", "источник"))
    хранение.требовать(текст.count("<fum_layer_assignment>") == текст.count("</fum_layer_assignment>") == 1
                       and текст.endswith(поручение_слоя.КОНЕЦ), "Нет единственного завершающего блока назначения")
    префикс, разделитель, данные = текст.partition(поручение_слоя.НАЧАЛО)
    хранение.требовать(bool(разделитель) and bool(префикс), "Нет первоначального текста поручения")
    байты = данные.removesuffix(поручение_слоя.КОНЕЦ).encode("utf-8")
    блок = хранение.разобрать(байты)
    поля = {"схема", "корневая_задача", "база", "файлы", "план", "слой", "назначение"}
    if блок.get("схема") == "fum.первоначальное-назначение-слоя.2":
        поля.add("профиль_модели")
    хранение.поля(блок, поля)
    хранение.требовать(блок["схема"] in {"fum.первоначальное-назначение-слоя.1", "fum.первоначальное-назначение-слоя.2"}
                       and блок["корневая_задача"] == отправитель and хранение.байты(блок) == байты,
                       "Неканоническое либо чужое назначение")
    if блок["схема"] == "fum.первоначальное-назначение-слоя.2":
        хранение.требовать(блок["профиль_модели"] == {"model": "gpt-6-luna", "thinking": "low"},
                           "Неизвестный профиль модели в назначении")
    return {"назначение": блок, "текст": текст, "источник": граница}

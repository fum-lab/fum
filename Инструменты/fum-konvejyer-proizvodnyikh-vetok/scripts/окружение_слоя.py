"""Подготовить закреплённую зависимость собственного слоя до установки Журнала."""
import hashlib
import importlib.util
import os
from pathlib import Path
import stat
import sys
import time

import дочернее_назначение
import приём_направления as хранение


ПУТЬ_ИНСТРУМЕНТА = Path(__file__).resolve().parents[2] / 'fum-proverka-git-zavisimostej/scripts/proveritj-git-zavisimostj.py'
спецификация = importlib.util.spec_from_file_location('зависимости_окружения_слоя', ПУТЬ_ИНСТРУМЕНТА)
зависимости = importlib.util.module_from_spec(спецификация)
sys.modules[спецификация.name] = зависимости
спецификация.loader.exec_module(зависимости)
КОД = {Path(имя).resolve(): hashlib.sha256(Path(имя).read_bytes()).hexdigest()
       for имя in (__file__, зависимости.__file__)}


def отпечаток_файла(путь):
    хранение.безопасный_путь(путь)
    if not путь.exists():
        return None
    хранение.требовать(stat.S_ISREG(путь.lstat().st_mode), 'Защищённый путь не является обычным файлом')
    return hashlib.sha256(путь.read_bytes()).hexdigest()


def защищённое_состояние(корень, собственный, общий):
    return {
        'конфигурация': отпечаток_файла(общий / 'config'),
        'конфигурация_дерева': отпечаток_файла(собственный / 'config.worktree'),
        'gitmodules': отпечаток_файла(корень / '.gitmodules'),
        'индекс': hashlib.sha256(хранение.гит(корень, 'ls-files', '--stage', '-v', '-z', сырые=True)).hexdigest(),
        'HEAD': хранение.гит(корень, 'rev-parse', 'HEAD').strip(),
        'ref': хранение.гит(корень, 'symbolic-ref', 'HEAD').strip(),
    }


def подготовить(корень, задача, источник, путь):
    начало = time.monotonic_ns()
    назначение = дочернее_назначение.прочитать(корень, задача, источник)
    корень = Path(назначение['писатель']['путь'])
    хранение.требовать(not (корень / назначение['каталоги'][1]).exists(),
                       'Окружение готовится до установки собственного Журнала')
    хранение.требовать(type(путь) is str and путь and Path(путь).as_posix() == путь
                       and not any(ord(знак) < 32 for знак in путь), 'Неканонический путь зависимости')
    хранение.требовать(not зависимости.validate_dependency_path(путь), 'Небезопасный путь зависимости')
    хранение.требовать(not any(путь.startswith(п) or п.startswith(путь + '/')
                              for п in назначение['каталоги']), 'Зависимость пересекает область записи слоя')
    for файл, хэш in КОД.items():
        хранение.безопасный_путь(файл)
        хранение.требовать(hashlib.sha256(файл.read_bytes()).hexdigest() == хэш, 'Код подготовки изменён после импорта')
    собственный = Path(хранение.гит(корень, 'rev-parse', '--absolute-git-dir').strip())
    общий = Path(хранение.гит(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').strip())
    хранение.требовать(собственный != общий, 'Подготовка слоя требует отдельного linked worktree')
    до = защищённое_состояние(корень, собственный, общий)
    хранение.требовать(до['HEAD'] == назначение['база'], 'Начальный HEAD уже не равен C')
    описание, ошибки = зависимости.registered_dependency_spec(корень, путь)
    хранение.требовать(описание is not None and not ошибки, '; '.join(ошибки))
    запись_C = хранение.гит(корень, 'ls-tree', назначение['база'], '--', путь).strip()
    хранение.требовать(запись_C == '160000 commit ' + описание.revision + '\t' + путь,
                       'Gitlink C и индекса не совпадает')
    хранение.гит(корень, 'diff', '--exit-code', назначение['база'], '--', '.gitmodules', путь)
    привязка = хранение.хэш(дочернее_назначение.привязка(назначение))
    ожидаемое = {'назначение_sha256': привязка, 'путь': путь, 'gitlink': описание.revision, 'защищённое': до}
    каталог = собственный / 'fum-окружение-слоя-v1'
    квитанция = каталог / (хранение.хэш({'назначение': привязка, 'путь': путь}) + '.json')
    хранение.безопасный_путь(каталог, каталог=True)
    хранение.безопасный_путь(квитанция)
    if квитанция.exists():
        прежняя = хранение.разобрать(квитанция.read_bytes())
        хранение.требовать(прежняя.get('схема') == 'fum.окружение-слоя.1'
                           and прежняя.get('состояние') == 'проверен' and прежняя.get('ожидание') == ожидаемое,
                           'Прежняя попытка подготовки не допускает повтор')
        ошибки = зависимости.validate_dependency(корень, описание)
        хранение.требовать(not ошибки, '; '.join(ошибки))
        хранение.требовать(защищённое_состояние(корень, собственный, общий) == до
                           and дочернее_назначение.прочитать(корень, задача, источник) == назначение,
                           'Состояние изменилось при проверке готового окружения')
        return прежняя
    зависимость = корень / путь
    готовая = os.path.lexists(зависимость / '.git')
    if not готовая:
        ошибки = зависимости.validate_dependency_worktree_location(корень, зависимость, путь)
        хранение.требовать(not ошибки, '; '.join(ошибки))
        хранение.требовать(not зависимость.exists() or (зависимость.is_dir() and not any(зависимость.iterdir())),
                           'Каталог неподготовленной зависимости занят')
    хранение.требовать(дочернее_назначение.прочитать(корень, задача, источник) == назначение,
                       'Назначение изменилось до подготовки окружения')
    хранение.создать_каталоги(каталог, собственный, права=0o700)
    результат = {'схема': 'fum.окружение-слоя.1', 'ожидание': ожидаемое, 'состояние': 'намерение'}
    with os.fdopen(os.open(квитанция, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600), 'wb') as поток:
        поток.write(хранение.байты(результат)); поток.flush(); os.fsync(поток.fileno())
    хранение.синхронизировать_каталог(каталог)
    try:
        if готовая:
            ошибки = зависимости.validate_dependency(корень, описание)
        else:
            _, ошибки = зависимости.initialize_registered_dependency(корень, путь)
        хранение.требовать(not ошибки, '; '.join(ошибки))
        хранение.требовать(защищённое_состояние(корень, собственный, общий) == до,
                           'Подготовка изменила защищённое состояние superproject')
        хранение.требовать(дочернее_назначение.прочитать(корень, задача, источник) == назначение,
                           'Назначение изменилось после подготовки окружения')
        результат.update(состояние='проверен', длительность_наносекунды=time.monotonic_ns() - начало,
                         материализация=not готовая)
        хранение.установить(квитанция, хранение.байты(результат))
        return результат
    except BaseException:
        результат.update(состояние='не завершено', длительность_наносекунды=time.monotonic_ns() - начало)
        хранение.установить(квитанция, хранение.байты(результат))
        raise

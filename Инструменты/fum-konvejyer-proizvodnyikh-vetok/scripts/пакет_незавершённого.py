"""Прочитать независимые рабочие и индексные байты без записи в Git."""
import hashlib
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-reyestr-planirovaniya/scripts'))
import приём_направления as хранение
import снимок_области
from паспорт_конвейера import _безопасный_относительный_путь

СХЕМА = 'fum.пакет-незавершённых-результатов.1'


def _каталоги(значение):
    хранение.требовать(type(значение) is list and значение and all(type(имя) is str for имя in значение)
                       and len(set(значение)) == len(значение),
                       'Нужны различные назначенные каталоги')
    for имя in значение:
        хранение.требовать(type(имя) is str and имя.endswith('/'), 'Нужен каталог с завершающим слешем')
        хранение.требовать(хранение.текст(имя), 'Недопустимый каталог')
        _безопасный_относительный_путь(имя, 'Каталог пакета', каталог=True)
    return значение


def проверить(описание, данные):
    """Целостность пакета не доказывает назначения или остановки писателя."""
    хранение.поля(описание, {'схема', 'база', 'каталоги', 'снимок', 'файлы', 'разрешение_установки', 'sha256'})
    хранение.требовать(описание['схема'] == СХЕМА and описание['разрешение_установки'] is False,
                       'Неизвестный пакет или недопустимое разрешение установки')
    хранение.требовать(хранение.шестнадцатеричный(описание['база'], 40), 'Нужен исходный OID')
    _каталоги(описание['каталоги'])
    снимок = описание['снимок']
    хранение.поля(снимок, {'владелец', 'индекс_sha256', 'статус_sha256', 'границы', 'файлы'})
    владелец = снимок['владелец']
    хранение.поля(владелец, {'задача', 'путь', 'ref', 'HEAD'})
    хранение.требовать(хранение.идентификатор_задачи(владелец['задача'])
                       and хранение.абсолютный_корень(владелец['путь'])
                       and хранение.ветка_писателя(владелец['ref'])
                       and владелец['HEAD'] == описание['база'], 'Неполный владелец снимка')
    хранение.поля(снимок['границы'], {'база_HEAD', 'HEAD_индекс', 'индекс_файлы'})
    хранение.требовать(all(хранение.шестнадцатеричный(значение) for значение in
                       [снимок['индекс_sha256'], снимок['статус_sha256'], *снимок['границы'].values()]),
                       'Неверные хэши границ снимка')
    хранение.требовать(type(описание['файлы']) is dict and type(данные) is dict
                       and type(снимок['файлы']) is dict
                       and set(описание['файлы']) == set(снимок['файлы']), 'Неполный состав пакета')
    хэши = set()
    for имя, версии in описание['файлы'].items():
        хранение.требовать(хранение.текст(имя), 'Недопустимый путь пакета')
        _безопасный_относительный_путь(имя, 'Файл пакета')
        хранение.требовать(any(имя.startswith(каталог) for каталог in описание['каталоги']), 'Путь вне пакета')
        хранение.поля(версии, {'индекс', 'рабочий'})
        исходный = описание['снимок']['файлы'][имя]
        рабочий = версии['рабочий']
        if рабочий is not None:
            хранение.поля(рабочий, {'режим', 'sha256'})
            хранение.требовать(type(рабочий['режим']) is int and 0 <= рабочий['режим'] <= 0o7777, 'Неверный режим файла')
            хранение.требовать(хранение.шестнадцатеричный(рабочий['sha256']), 'Неверный хэш рабочего файла')
            хэши.add(рабочий['sha256'])
        хранение.требовать(исходный == ({'тип': 'отсутствует'} if рабочий is None else {'тип': 'файл', **рабочий}),
                           'Рабочие байты расходятся со снимком')
        индекс = версии['индекс']
        if индекс is not None:
            хранение.поля(индекс, {'режим', 'oid', 'sha256'})
            хранение.требовать(type(индекс['режим']) is str and индекс['режим'] in {'100644', '100755'}
                               and хранение.шестнадцатеричный(индекс['oid'], 40)
                               and хранение.шестнадцатеричный(индекс['sha256']), 'Неверный stage-0')
            хэши.add(индекс['sha256'])
    хранение.требовать(set(данные) == хэши, 'Неполные либо лишние объекты пакета')
    for хэш, байты in данные.items():
        хранение.требовать(хранение.шестнадцатеричный(хэш, 64) and type(байты) is bytes
                           and hashlib.sha256(байты).hexdigest() == хэш, 'Повреждены байты объекта')
    for версии in описание['файлы'].values():
        индекс = версии['индекс']
        if индекс is not None:
            байты = данные[индекс['sha256']]
            заголовок = b'blob ' + str(len(байты)).encode('ascii') + b'\0'
            хранение.требовать(hashlib.sha1(заголовок + байты).hexdigest() == индекс['oid'],
                               'OID stage-0 не соответствует сохранённым байтам')
    ожидаемый = хранение.хэш({к: в for к, в in описание.items() if к != 'sha256'})
    хранение.требовать(описание['sha256'] == ожидаемый, 'Повреждено описание пакета')
    return ожидаемый


def собрать(корень, задача, база, каталоги):
    корень = Path(корень).absolute()
    _каталоги(каталоги)
    до = снимок_области.снимок(корень, задача, база, каталоги)
    хранение.требовать(до['владелец']['HEAD'] == база, 'Поддерживается незавершённое дерево на исходном C')
    индекс = хранение.гит(корень, 'ls-files', '--stage', '-z', сырые=True)
    хранение.требовать(hashlib.sha256(индекс).hexdigest() == до['индекс_sha256'], 'Индекс сдвинулся до чтения')
    записи = {}
    for строка in индекс.split(b'\0'):
        if not строка:
            continue
        мета, имя = строка.split(b'\t', 1)
        режим, объект, стадия = мета.decode('ascii').split()
        хранение.требовать(стадия == '0', 'Конфликтный индекс')
        записи[имя.decode('utf-8')] = (режим, объект)
    файлы, данные = {}, {}
    for имя, состояние in до['файлы'].items():
        версии = {'рабочий': None, 'индекс': None}
        хранение.требовать(состояние['тип'] in {'файл', 'отсутствует'}, 'В пакете ожидаются обычные файлы')
        if состояние['тип'] == 'файл':
            путь = корень / имя
            хранение.безопасный_путь(путь)
            байты = путь.read_bytes()
            хэш = hashlib.sha256(байты).hexdigest()
            хранение.требовать(хэш == состояние['sha256'], 'Рабочий файл сдвинулся во время чтения')
            данные[хэш] = байты
            версии['рабочий'] = {к: в for к, в in состояние.items() if к != 'тип'}
        if имя in записи:
            режим, объект = записи[имя]
            хранение.требовать(режим in {'100644', '100755'} and хранение.шестнадцатеричный(объект, 40), 'Неподдержанный объект индекса')
            байты = хранение.гит(корень, 'cat-file', 'blob', объект, сырые=True)
            хэш = hashlib.sha256(байты).hexdigest()
            данные[хэш] = байты
            версии['индекс'] = {'режим': режим, 'oid': объект, 'sha256': хэш}
        файлы[имя] = версии
    хранение.требовать(снимок_области.снимок(корень, задача, база, каталоги) == до, 'Вход пакета сдвинулся во время чтения')
    описание = {'схема': СХЕМА, 'база': база, 'каталоги': list(каталоги), 'снимок': до,
                'файлы': файлы, 'разрешение_установки': False}
    описание['sha256'] = хранение.хэш(описание)
    проверить(описание, данные)
    return описание, данные

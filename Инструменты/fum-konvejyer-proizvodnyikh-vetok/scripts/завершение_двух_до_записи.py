"""Честное закрытие двух созданных задач, остановленных до первой записи."""
import copy
import hashlib
import os
from pathlib import Path

import приём_направления as хранение
from отложенные_назначения import извлечь_ответ
import возобновления_до_записи
import нативные_вызовы
import остановка_ребёнка
import раздельные_ожидания
import завершение_сохранённых_писателей
import терминал_запуска

КОД = {Path(м.__file__).resolve(): hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
    for м in (возобновления_до_записи, нативные_вызовы, остановка_ребёнка,
              раздельные_ожидания, завершение_сохранённых_писателей, терминал_запуска)}
КОД[Path(__file__).resolve()] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def _ветки(исполнитель, вход, план, состояние):
    координатор = завершение_сохранённых_писателей._координатор(исполнитель, вход, план, состояние)
    ветки = {в.casefold() for в in хранение.гит(исполнитель.корень, 'for-each-ref', '--format=%(refname)', 'refs/heads/').splitlines()}
    писатели = состояние['писатели']
    for слой in план['описание']['слои']:
        ветка = слой['ветка'].casefold()
        хранение.требовать(ветка not in ветки and not any(п['ref'].casefold() == ветка for п in писатели.values()),
            'Назначенная ветка уже создана или имеет зарегистрированного писателя')
    хранение.требовать(not any(с['корень'] in писатели for с in вход['слои'].values()), 'Детское дерево уже имеет зарегистрированного писателя')
    return координатор


def _план(исполнитель, вход, состояние):
    хранение.поля(вход, {'схема', 'запуск', 'план_sha256', 'координатор', 'источник', 'ожидания', 'слои', 'возобновления', 'свидетельство_координатора'})
    хранение.требовать(вход['схема'] == 'fum.завершение-неудачного-запуска.5', 'Неизвестный переход двух задач до записи')
    запись = исполнитель._прочитать(состояние, вход['запуск']); план = запись['план']
    хранение.требовать(план['sha256'] == вход['план_sha256']
        and запись['смысл']['схема'] in {'fum.запуск-двух-слоёв.2', 'fum.запуск-двух-слоёв.3', 'fum.запуск-двух-слоёв.4', 'fum.запуск-двух-слоёв.5', 'fum.запуск-двух-слоёв.6'}
        and set(запись['наблюдения']) == {'события', 'сообщения'} and all(н is None for н in запись['наблюдения'].values()),
        'Нужен полный запуск без раннего назначения обоих писателей')
    попытки = {слой: состояние['попытки'].get(ключ) for слой, ключ in план['попытки'].items()}
    история = хранение.хэш({'запись': запись, 'попытки': попытки})
    прежний = терминал_запуска.прочитать(состояние, вход['запуск'])
    if прежний is not None:
        хранение.требовать(прежний['схема'] == терминал_запуска.СХЕМА_ДВУХ_ДО_ЗАПИСИ
            and прежний['вход_sha256'] == хранение.хэш(вход) and прежний['история_sha256'] == история,
            'Повтор изменил терминал или историю запуска')
        return copy.deepcopy(прежний), []
    аттестация = {'задача': исполнитель.задача, 'единственный_координатор': True,
        'нет_незаписанных_или_выполняющихся_вызовов': True, 'ребёнок_не_возобновляется': True}
    хранение.требовать(вход['свидетельство_координатора'] == аттестация, 'Нет кооперативной аттестации остановки')
    хранение.поля(вход['слои'], попытки)
    база = план['координатор']['HEAD']; дети, корни = [], []
    for имя, слой in вход['слои'].items():
        хранение.поля(слой, {'вид', 'попытка', 'задача', 'корень', 'источник'})
        попытка = попытки[имя]
        хранение.требовать(слой['вид'] == 'остановлен-до-записи' and type(попытка) is dict
            and слой['попытка'] == попытка['попытка'] and попытка['аргументы'] == план['аргументы'][имя]
            and попытка['база'] == база and type(попытка['ответ']) is dict,
            'Оба допуска должны иметь настоящий сохранённый ответ создания')
        дети.append(слой['задача']); корни.append(слой['корень'])
    хранение.требовать(len(set(дети)) == len(set(корни)) == 2, 'Повтор UUID или дерева ребёнка')
    координатор = _ветки(исполнитель, вход, план, состояние)
    исполнитель._инструменты(координатор['HEAD'])
    for путь, хэш in КОД.items():
        хранение.безопасный_путь(путь)
        хранение.требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == хэш, 'Код завершения изменился после загрузки')
    нативный = нативные_вызовы.прочитать(вход['источник'], исполнитель.задача,
        аргументы=[п['аргументы'] for п in попытки.values()], ожидания=дети, интервалы=True)
    ожидания = раздельные_ожидания.проверить(нативный, вход['ожидания'], дети)
    результаты, сверки = {}, []
    for имя, слой in вход['слои'].items():
        попытка = попытки[имя]
        вызовы = [в for в in нативный['вызовы'] if в['аргументы'] == попытка['аргументы']]
        хранение.требовать(len(вызовы) == 1 and извлечь_ответ(вызовы[0]['ответ']) == попытка['ответ'],
            'Нет единственного точного создания и сохранённого ответа ребёнка')
        ответ = попытка['ответ']
        хранение.требовать(not ответ.get('противоречивые_идентификаторы')
            and ответ.get('threadId') in (None, слой['задача']), 'Ответ создания противоречит UUID ребёнка')
        аргументы = (исполнитель, слой, база, попытка['аргументы']['prompt'], ожидания[слой['задача']])
        профиль = {'модель': попытка['аргументы']['model'], 'усилие': попытка['аргументы']['thinking']}
        остановка = остановка_ребёнка.проверить(*аргументы, **профиль)
        результаты[имя] = {'вид': слой['вид'], 'попытка': слой['попытка'], 'вызов': вызовы[0]['источник'], 'остановка': остановка}
        сверки.append((имя, аргументы, профиль))
    возобновления = возобновления_до_записи.проверить(исполнитель, вход, нативный, попытки)
    хранение.требовать(_ветки(исполнитель, вход, план, состояние) == координатор, 'Координатор изменился при проверке')
    квитанция = {'схема': терминал_запуска.СХЕМА_ДВУХ_ДО_ЗАПИСИ, 'запуск': вход['запуск'], 'план_sha256': план['sha256'],
        'вход_sha256': хранение.хэш(вход), 'история_sha256': история, 'координатор': координатор,
        'слои': результаты, 'возобновления': возобновления, 'источник': нативный['источник'],
        'ожидания': {з: {к: о[к] for к in ('id', 'источник', 'интервал')} for з, о in ожидания.items()},
        'свидетельство_координатора': аттестация, 'отсутствие_незаписанного_вызова_доказано': False}
    return {**квитанция, 'sha256': хранение.хэш(квитанция)}, сверки


def предпросмотр(исполнитель, вход):
    return _план(исполнитель, вход, исполнитель.хранилище.прочитать())[0]


def _снимок_корня(описание):
    """Повторный SHA доказывает тождество уже разобранных байтов без второго JSON-разбора."""
    путь = Path(описание['путь']); хранение.безопасный_путь(путь)
    хэш = hashlib.sha256()
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        хранение.требовать(до.st_size == описание['граница'], 'Снимок корня сдвинулся перед терминалом')
        while блок := поток.read(4 * 1024 * 1024):
            хэш.update(блок)
        после = путь.stat()
        метка = lambda с: (с.st_dev, с.st_ino, с.st_size, с.st_mtime_ns, с.st_ctime_ns)
        хранение.требовать(метка(до) == метка(после) == метка(os.fstat(поток.fileno()))
            and хэш.hexdigest() == описание['sha256'], 'Снимок корня изменился перед терминалом')


def завершить(исполнитель, вход, ожидаемый_sha256):
    with исполнитель.хранилище.изменить() as состояние:
        результат, сверки = _план(исполнитель, вход, состояние)
        хранение.требовать(результат['sha256'] == ожидаемый_sha256, 'Изменён просмотренный переход до записи')
        ключ = терминал_запуска.ключ(вход['запуск'])
        if ключ not in состояние['приёмы']:
            for имя, аргументы, профиль in сверки:
                хранение.требовать(остановка_ребёнка.проверить(*аргументы, **профиль) == результат['слои'][имя]['остановка'],
                    'Остановленный ребёнок изменился перед записью терминала')
            _снимок_корня(вход['источник'])
            план = исполнитель._прочитать(состояние, вход['запуск'])['план']
            хранение.требовать(_ветки(исполнитель, вход, план, состояние) == результат['координатор'],
                'Ветки изменились перед записью терминала')
            исполнитель.хранилище.проверить_владельца_под_замком(состояние,
                ожидаемый_коммит=вход['координатор']['HEAD'], ожидаемая_ветка=вход['координатор']['ref'])
            состояние['приёмы'][ключ] = результат
        return copy.deepcopy(результат)

"""Ядро эффекта для доверенного принимающего адаптера, не самостоятельный допуск.

Все импорты и callback допуска загружаются принимающей стороной до merge.
Публичного CLI нет: происхождение ревью и принятый код связывает вызывающий.
"""
import hashlib
import json
import os
from pathlib import Path
import stat
import time

import создание_коммита as создатель
from наблюдение_обратного_приёма import _ветки, _гит, _рабочее_состояние, _текст, _требовать, снять_состояние
from настройки_обратного_приёма import проверить_настройки
from фаза_обратного_приёма import проверить_готовое_слияние


def _байты(данные):
    return (json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()


def _сохранить(путь, сырые):
    создатель.модели.сохранить_сообщение(путь, сырые.decode())
    каталог = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(каталог)
    finally:
        os.close(каталог)


def _синхронизировать_каталоги(каталог):
    for путь in (каталог, *каталог.parents):
        дескриптор = os.open(путь, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(дескриптор)
        finally:
            os.close(дескриптор)


def _среда(автор, коммиттер):
    среда = {к: з for к, з in os.environ.items()
             if not к.startswith("GIT_") or к in {"GIT_CONFIG_GLOBAL", "GIT_CONFIG_NOSYSTEM"}}
    среда.update(GIT_NO_REPLACE_OBJECTS="1", GIT_NO_LAZY_FETCH="1", GIT_OPTIONAL_LOCKS="0")
    for роль, данные in (("AUTHOR", автор), ("COMMITTER", коммиттер)):
        _требовать(type(данные) is list and len(данные) == 4
                  and all(type(часть) is str and часть for часть in данные), "Неполная идентичность")
        среда["GIT_" + роль + "_NAME"] = данные[0]
        среда["GIT_" + роль + "_EMAIL"] = данные[1]
        среда["GIT_" + роль + "_DATE"] = " ".join(данные[2:])
    return среда


def _вход(корень, план, каталог, сообщение, автор, коммиттер, сверить_основание):
    _требовать(callable(сверить_основание), "Нужен независимый проверяющий основания")
    сверить_основание()
    корень, каталог = Path(корень), Path(каталог)
    for путь in (корень, каталог):
        _требовать(путь.is_absolute() and путь.resolve(strict=True) == путь and путь.is_dir(),
                  "Нужны физические абсолютные каталоги")
    _требовать(not any(os.path.lexists(п / ".git") for п in (каталог, *каталог.parents)),
              "Каталог операции должен быть вне Git")
    _требовать(not any((п / "HEAD").is_file() and (п / "objects").is_dir()
                      for п in (каталог, *каталог.parents)),
              "Каталог операции должен быть вне Git, включая bare")
    состояние = каталог.stat()
    _требовать(состояние.st_uid == os.getuid() and stat.S_IMODE(состояние.st_mode) == 0o700,
              "Нужен собственный приватный каталог")
    _требовать(type(план) is dict and план.get("схема") == "fum.план-обратного-приёма.1"
              and план.get("разрешение_записи") is False and план.get("повторный_полный_прогон") is False,
              "Нужен проверенный чистый план и отдельный допуск")
    _требовать(план["родители"] == [план["получатель"]["коммит"], план["источник"]["коммит"]]
              and план["дерево"] == план["источник"]["дерево"]
              and план["ветка"] == план["получатель"]["ветка"], "План внутренне противоречив")
    _требовать(type(сообщение) is bytes and сообщение.endswith(b"\n") and b"\0" not in сообщение,
              "Нужно полное сообщение коммита")
    сообщение.decode("utf-8")
    среда = _среда(автор, коммиттер)
    _требовать(создатель.проверить_формат(автор[0]), "Неверное имя автора")
    имя = создатель.ПОЛНОЕ_ИМЯ.fullmatch(автор[0])
    _требовать(имя is not None and имя[1] == "FUM Codex", "Нужна роль FUM Codex с моделью и усилием")
    данные = {"схема": "fum.намерение-обратного-приёма.1", "корень": str(корень),
              "план": план, "сообщение_sha256": hashlib.sha256(сообщение).hexdigest(),
              "автор": автор, "коммиттер": коммиттер}
    подготовка = {"сообщение_sha256": данные["сообщение_sha256"], "имя_автора": автор[0],
                  "исходный_автор": автор, "исходный_коммиттер": коммиттер,
                  "явные_даты": {к: среда[к] for к in ("GIT_AUTHOR_DATE", "GIT_COMMITTER_DATE")}}
    параметры = {"ветка": план["ветка"], "исходный_коммит": план["получатель"]["коммит"],
                 "родители": план["родители"], "имя_автора": "FUM Codex",
                 "сообщение": str(каталог / "сообщение.txt")}
    return корень, каталог, _байты(данные), подготовка, параметры, среда


def _конечное_состояние(корень, план):
    голова = _текст(корень, "rev-parse", "HEAD")
    получатель = {**план["получатель"], "коммит": голова, "дерево": план["дерево"]}
    _ветки(корень, получатель, план["источник"])
    _рабочее_состояние(корень)
    _ветки(корень, получатель, план["источник"])


def применить(корень, план, каталог, сообщение, автор, коммиттер, *, сверить_основание):
    """Одна новая попытка. Существующий каталог попытки не переиспользуется."""
    начало = time.perf_counter_ns()
    корень, каталог, намерение, подготовка, параметры, среда = _вход(
        корень, план, каталог, сообщение, автор, коммиттер, сверить_основание)
    _требовать(not list(каталог.iterdir()), "Существует попытка; новое применение запрещено")
    настройки = проверить_настройки(корень)
    наблюдение = снять_состояние(корень, план["получатель"], план["источник"])
    _требовать(наблюдение["разница_sha256"] == план["разница_sha256"], "Изменилась полная разница")
    for роль, ожидаемое in (("AUTHOR", автор), ("COMMITTER", коммиттер)):
        _требовать(создатель.идентичность(корень, "GIT_" + роль + "_IDENT", среда) == ожидаемое,
                  "Git не подтвердил выбранную идентичность")

    def сверить_вход():
        сверить_основание()
        _требовать(_байты({"схема": "fum.намерение-обратного-приёма.1", "корень": str(корень),
            "план": план, "сообщение_sha256": hashlib.sha256(сообщение).hexdigest(),
            "автор": автор, "коммиттер": коммиттер}) == намерение, "Изменились выбранные входы")
        _требовать(проверить_настройки(корень) == настройки, "Изменились настройки Git")
        _требовать(создатель.прочитать(каталог / "намерение.json", приватный=True) == намерение
                  and создатель.прочитать(параметры["сообщение"], приватный=True) == сообщение,
                  "Изменились сохранённые входы")

    def гит(корень, *аргументы, среда=среда):
        return создатель.гит(корень, *аргументы, среда=среда,
                             параметры_гита=("-c", "core.fsmonitor=false", "-c", "submodule.recurse=false",
                                             "-c", "maintenance.auto=false", "-c", "gc.auto=0"))

    _синхронизировать_каталоги(каталог)
    _сохранить(каталог / "намерение.json", намерение)
    _сохранить(каталог / "сообщение.txt", сообщение)
    сверить_вход()
    _требовать(снять_состояние(корень, план["получатель"], план["источник"]) == наблюдение,
              "Состояние изменилось перед merge")
    try:
        гит(корень, "merge", "--no-commit", "--no-ff", "--no-edit", "--no-overwrite-ignore",
            план["источник"]["коммит"])
    except создатель.ОшибкаКоммита as ошибка:
        _сохранить(каталог / "процесс-merge.json", _байты(ошибка.процесс))
        raise
    _сохранить(каталог / "процесс-merge.json", _байты({"код": 0, "тайм_аут": False,
              "исполнение_завершено": True, "прерывание": None}))
    фаза = проверить_готовое_слияние(корень, план["получатель"], план["источник"])

    def последний_допуск():
        сверить_вход()
        _требовать(проверить_готовое_слияние(корень, план["получатель"], план["источник"]) == фаза,
                  "Изменилась фаза слияния")

    def после_эффекта(квитанция):
        сверить_вход()
        _конечное_состояние(корень, план)

    return создатель.выполнить_эффект(корень, параметры, подготовка, намерение, сообщение,
        каталог / "квитанция.json", [п["идентификатор"] for п in план["проверки"]],
        {"план_sha256": hashlib.sha256(_байты(план)).hexdigest()}, фаза["индекс_sha256"], None,
        автор, коммиттер, среда, начало, [], последний_допуск,
        читать_гит=гит, ожидаемое_дерево=план["дерево"], после_эффекта=после_эффекта)


def повтор(корень, план, каталог, сообщение, автор, коммиттер, *, сверить_основание):
    """Только чтение подтверждённого успеха; UNKNOWN не возобновляется."""
    корень, каталог, намерение, подготовка, параметры, _ = _вход(
        корень, план, каталог, сообщение, автор, коммиттер, сверить_основание)
    _требовать(создатель.прочитать(каталог / "намерение.json", приватный=True) == намерение
              and создатель.прочитать(каталог / "сообщение.txt", приватный=True) == сообщение,
              "Вход отличается от сохранённой попытки")
    процесс = создатель.прочитать(каталог / "процесс-merge.json", приватный=True)
    _требовать(процесс == _байты({"код": 0, "тайм_аут": False, "исполнение_завершено": True, "прерывание": None}),
              "Нет подтверждённого успеха merge")
    путь = каталог / "квитанция.json"
    _требовать(путь.is_file(), "Нет завершённой квитанции; повтор запрещён")
    сырые = создатель.прочитать(путь, приватный=True)
    квитанция = json.loads(сырые)
    _требовать(квитанция.get("подготовка_sha256") == hashlib.sha256(намерение).hexdigest()
              and квитанция.get("ожидание", {}).get("дерево") == план["дерево"]
              and квитанция.get("допуск") == {"план_sha256": hashlib.sha256(_байты(план)).hexdigest()},
              "Квитанция не связана с выбранным приёмом")
    создатель.сверить_ожидание_квитанции(квитанция, подготовка, параметры)
    результат = создатель.восстановить(корень, квитанция, путь, читать_гит=_гит)
    проверить_настройки(корень)
    _конечное_состояние(корень, план)
    сверить_основание()
    _требовать(создатель.прочитать(путь, приватный=True) == сырые, "Квитанция изменилась при повторе")
    return результат

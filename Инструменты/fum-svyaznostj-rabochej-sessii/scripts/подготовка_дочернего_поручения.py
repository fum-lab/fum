def поля(значение, ожидаемые):
    требовать(type(значение) is dict and set(значение) == set(ожидаемые), 'неверные поля композиции')


def разобрать_время(вывод):
    """Настоящий --format both: две строки prefix= и label=, не JSON."""
    строки = вывод.splitlines()
    требовать(len(строки)==2 and строки[0].startswith('prefix=') and строки[1].startswith('label='),
        'нужны обе строки get-session-time')
    время = этап.свежесть.parse_display_time(строки[1][6:])
    требовать(этап.свежесть.format_msk(время)==строки[1][6:]
        and время.strftime('%Y-%m-%d_%H-%M-%S_MSK')==строки[0][7:], 'несогласованные строки времени')
    return строки[0][7:], строки[1][6:]


def источник(корень, выбор):
    поля(выбор, {'коммит', 'путь', 'sha256'})
    обычное.история.полный_идентификатор(выбор['коммит'])
    обычное.путь(корень, выбор['путь'])
    сырые = обычное.делегация.сверить_источник(корень, выбор)
    коммит = обычное.история.прочитать_объекты(корень, [выбор['коммит']], 'commit')[выбор['коммит']]
    дерево = [с[5:].decode() for с in коммит.split(b'\n\n', 1)[0].splitlines() if с.startswith(b'tree ')]
    требовать(len(дерево) == 1, 'неверное дерево источника')
    состояние = обычное.история.состояния_пути(корень, {выбор['коммит']: дерево[0]}, выбор['путь'])[выбор['коммит']]
    хэш_содержания = None
    if выбор['путь'].endswith('.md'):
        текст = сырые.decode()
        основа, _, повреждён = этап.свежесть.split_recency_block(текст, путь=Path(выбор['путь']), корень=корень)
        требовать(not повреждён, 'повреждённый recency источника')
        хэш_содержания = этап.свежесть.content_digest(этап.свежесть.canonical_content(основа))
    return сырые, {**выбор, 'сырой_sha256': хэш(сырые), 'хэш_содержимого': хэш_содержания,
        'объект': состояние[1], 'байтов': len(сырые)}


def публикация(корень, файлы):
    """Действующая адресная политика на будущих публичных путях."""
    файл = ИНСТРУМЕНТЫ / 'fum-proverka-mashinno-lokaljnyikh-putej/scripts/proveritj-mashinno-lokaljnyiye-puti.py'
    описание = importlib.util.spec_from_file_location('публикация_поручения', файл)
    м = importlib.util.module_from_spec(описание); sys.modules[описание.name] = м
    прежние = list(sys.path)
    try:
        sys.path.insert(0, str(файл.parent)); описание.loader.exec_module(м)
    finally: sys.path[:] = прежние
    файл_политики = (корень / 'Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/policy.json'
        if (корень / 'Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/policy.json').is_file()
        else файл.parents[1] / 'policy.json')
    политика = м.load_policy(файл_политики)
    политика = м.выбрать_политику(политика, файлы)
    допуски_метаданных = м.позиции_метаданных(политика, файлы)
    кандидаты = [к for путь, сырые in файлы.items() for к in м.scan_text(путь, сырые.decode(),
        допущенные_метаданные=допуски_метаданных.get(путь, frozenset()))]
    кандидаты, отказы, отказ = м._apply_policy(кандидаты, политика, 'policy.json')
    требовать(not отказ and not отказы and not any(к.category.startswith('error.') for к in кандидаты),
        'публикационная проверка будущих материалов отказала')
    return {'проверенные_пути': sorted(файлы), 'кандидатов': len(кандидаты),
        'сценарий_sha256':хэш(файл.read_bytes()),'политика_sha256':хэш(файл_политики.read_bytes()),
        'граница': 'Адресная политика машинных путей; проверка содержания и полномочий остаётся у корня.'}


def собственное_дерево(вход):
    требовать(os.environ.get('CODEX_THREAD_ID') == обычное.идентичность(вход['писатель']), 'чужой писатель')
    запрещены = {'GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR',
        'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES', 'GIT_CONFIG_PARAMETERS',
        'GIT_CONFIG_COUNT', 'GIT_REPLACE_REF_BASE', 'GIT_SHALLOW_FILE', 'GIT_NAMESPACE'}
    требовать(not запрещены.intersection(os.environ), 'перенаправление Git запрещено')
    корень = этап.адреса.точный_абсолютный(вход['корень'])
    требовать(гит(корень, 'rev-parse', '--show-toplevel') == str(корень), 'иной checkout')
    ветка = гит(корень, 'symbolic-ref', 'HEAD')
    корневой = вход['фаза'] in {'постановка', 'акт'}
    требовать(ветка.startswith('refs/heads/codex/') or (корневой
        and ветка in {'refs/heads/fuma', 'refs/heads/planirovaniye'}), 'недопустимый собственный ref')
    владельцы = [д for д in гит(корень, 'worktree', 'list', '--porcelain').split('\n\n')
        if 'branch '+ветка in д.splitlines()]
    требовать(len(владельцы) == 1 and владельцы[0].splitlines()[0] == 'worktree '+str(корень), 'чужой владелец ref')
    каталог = Path(гит(корень, 'rev-parse', '--absolute-git-dir'))
    родители = None
    if вход.get('схема') == 'fum.подготовка-дочернего-поручения.2':
        требовать(вход['фаза'] == 'входы' and 'доставка' in вход, 'слияние разрешено только дочерним входам .2')
        sys.path.insert(0, str(ИНСТРУМЕНТЫ / 'fum-reyestr-planirovaniya/scripts'))
        import доставка_отчёта
        from приём_направления import ОшибкаПриёма
        try:
            родители = доставка_отчёта.слияние_генератора(корень, вход['доставка'], вход['писатель'])
        except ОшибкаПриёма as ошибка:
            raise ValueError(str(ошибка)) from ошибка
    else:
        требовать(not os.path.lexists(каталог/'MERGE_HEAD'), 'генератор требует обычный этап без MERGE_HEAD')
    требовать(not гит(корень, 'ls-files', '--unmerged', '-z'), 'unmerged index')
    снимок = {'HEAD': гит(корень, 'rev-parse', 'HEAD'), 'ref': ветка,
        'индекс_sha256': хэш(Path(гит(корень,'rev-parse','--path-format=absolute','--git-path','index')).read_bytes())}
    if родители is not None:
        снимок['родители'] = родители
    return корень, снимок


def снимок_композиции(вход, установки, зависимости, существующие, запрос, основание_переноса=None):
    """Метки уже прочитанных входов; source/cache не разбираются повторно."""
    корень=Path(вход['корень']); свои={Path(у['путь']) for у in установки}
    имена={корень/п for с in зависимости.values() for п in с.get('входы',{})}
    имена.update(корень/п for п in существующие)
    if основание_переноса is not None:
        имена.update(корень/п for п in основание_переноса['входы'])
    for и in вход['источники']: имена.update((Path(и['путь']),Path(и['кэш'])))
    if 'основание_координации' in вход:
        имена.update(Path(с['путь']) for с in вход['основание_координации']['оригиналы'])
    if 'доставка' in вход:
        имена.update(Path(с['путь']) for с in вход['доставка'].values())
        доставка = Path(вход['доставка']['квитанция']['путь']).parent
        имена.update(доставка / и for и in ('активная.json', 'получатель.json'))
    if 'перенос_модели' in вход:
        имена.update(Path(с['путь']) for с in вход['перенос_модели'].values())
    имена.add(Path(вход['каталог_выходов'])/'кэш-модели.json')
    имена.update(этап.каркас.КАТАЛОГ_ШАБЛОНОВ.glob('*.шаблон'))
    # Конечное замыкание импортов самого контура. Посторонние тесты и
    # профилировщики не меняют библиотечный план при его применении через CLI.
    очередь=[sys.modules[__name__],sys.modules.get('публикация_поручения')]; увиденные=set()
    while очередь:
        м=очередь.pop()
        if м is None or type(getattr(м,'__file__',None)) is not str: continue
        ф=Path(м.__file__).absolute()
        if not ф.is_relative_to(ИНСТРУМЕНТЫ) or 'tests' in ф.relative_to(ИНСТРУМЕНТЫ).parts or ф in увиденные: continue
        увиденные.add(ф); имена.add(ф)
        for з in vars(м).values():
            связанный=з if type(з) is type(sys) else sys.modules.get(getattr(з,'__module__',None))
            if связанный is not None: очередь.append(связанный)
    имена.add(Path(__file__).absolute())
    имена.add(ИНСТРУМЕНТЫ/'fum-proverka-mashinno-lokaljnyikh-putej/policy.json')
    политика=корень/'Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/policy.json'
    if os.path.lexists(политика): имена.add(политика)
    имена-=свои; метки={}
    каталог_проверок=обычное.путь(корень,((Path(запрос).parent/'материалы/запуски-проверок').as_posix()))
    родители={каталог_проверок,*каталог_проверок.parents}
    состав_проверок=sorted(ф.name for ф in каталог_проверок.iterdir()) if os.path.lexists(каталог_проверок) else None
    for ф in sorted(имена):
        родители.update(ф.parents)
        if os.path.lexists(ф):
            с=ф.lstat(); требовать(stat.S_ISREG(с.st_mode),'необычный вход композиции')
            метки[str(ф)]=[с.st_dev,с.st_ino,с.st_mode,с.st_uid,с.st_size,с.st_mtime_ns,с.st_ctime_ns]
        else: метки[str(ф)]=None
    for ф in sorted(родители):
        if os.path.lexists(ф):
            с=ф.lstat(); требовать(stat.S_ISDIR(с.st_mode),'symlink или необычный родитель композиции')
            # Собственная установка добавляет записи каталога. Его физическая
            # идентичность, тип, uid и mode обязаны сохраняться.
            метки[str(ф)]=[с.st_dev,с.st_ino,с.st_mode,с.st_uid]
        else: метки[str(ф)]=None
    исключённые={ф.relative_to(корень).as_posix() for ф in свои if ф.is_relative_to(корень)}
    инвентарь=sorted(ф.relative_to(корень).as_posix() for ф in этап.свежесть.find_markdown_paths(корень)
        if ф.relative_to(корень).as_posix() not in исключённые)
    return {'метки':метки,'инвентарь_документов':инвентарь,'история_проверок':состав_проверок}


def сверить_границу_установки(вход, план):
    корень,текущий=собственное_дерево(вход)
    требовать(текущий=={к:план['снимок'][к] for к in ('HEAD','ref','индекс_sha256', *(['родители'] if вход['схема'] == 'fum.подготовка-дочернего-поручения.2' else []))},'дрейф адреса установки')
    существующие=план['технические_входы']['снимок_существующих_записей']
    требовать(снимок_композиции(вход,план['установка'],план['зависимости'],существующие,план['технические_входы']['коммит']['запрос'],план['снимок']['основание_переноса'])==план['снимок']['композиция'],
        'дрейф входа композиции')
    for путь,сведения in существующие.items():
        ф=обычное.путь(корень,путь); с=ф.lstat()
        требовать(stat.S_ISREG(с.st_mode) and stat.S_IMODE(с.st_mode)==сведения['режим']
            and хэш(ф.read_bytes())==сведения['sha256'],'дрейф прежней записи v4')
    _,_,граница=обычное.постановка.прочитать_начало_источника(вход['источник_модели'])
    требовать(граница==план['снимок']['модель'],'дрейф нативного начала писателя')
    if план['нативная_привязка'] is not None:
        н=план['нативная_привязка']
        обычное.сверить_единый_снимок(вход['исполнитель']['источник_модели'],н['начало'],н['поручение'])
    for у in план['установка']:
        ф=Path(у['путь'])
        if у['слой']=='публичный': обычное.путь(корень,ф.relative_to(корень).as_posix())
        else: этап.приватный(ф,существует=False)
        if os.path.lexists(ф):
            с=ф.lstat(); требовать(stat.S_ISREG(с.st_mode) and stat.S_IMODE(с.st_mode)==у['режим']
                and хэш(ф.read_bytes())==у['sha256'],'коллизия на границе установки')


def проверить_решение(решение):
    новые=type(решение) is dict and решение.get('схема')=='fum.смысл-дочернего-поручения.2'
    поля(решение, {'схема','координатор','модель','усилие','постановка','поручение','акт','подготовка','зависимости'}
        | ({'координация'} if новые else set()))
    требовать(решение['схема'] in {'fum.смысл-дочернего-поручения.1','fum.смысл-дочернего-поручения.2'},
        'неверная схема решения')


def проверить_координацию(корень, решение, вход):
    новые=решение['схема']=='fum.смысл-дочернего-поручения.2'
    требовать(новые == (type(вход) is dict and вход.get('схема')=='fum.подготовка-дочернего-поручения.3'),
        'версия основания не совпала с семантическим и приватным входами')
    return координация.проверить(корень,решение,вход) if новые else None


def приглашение(решение, выбор, основание=None):
    требовать((основание is not None)==(решение['схема']=='fum.смысл-дочернего-поручения.2'),
        'приглашению требуется проверенное основание')
    return (решение['поручение'] + '\n\nПостановка: '+выбор['путь']+'\nКоммит: '+выбор['коммит']
        +'\nСырой SHA-256: '+выбор['sha256']+'\n'+(координация.блок(основание) if основание is not None else ''))


def составить_приглашение(корень, выбор_решения, выбор_постановки, вход_координации=None):
    """Читающая привязка текста после коммита постановки, до создания чата."""
    сырые, сведения = источник(корень,выбор_решения)
    решение = этап.коммит.сообщения._разобрать(сырые)
    проверить_решение(решение)
    основание=проверить_координацию(корень,решение,вход_координации)
    обычное.идентичность(решение['координатор']); поля(решение['постановка'],{'путь','текст'})
    требовать(type(решение['поручение']) is str and решение['поручение'].strip(),'пустое поручение')
    пост, сведения_поста = источник(корень,выбор_постановки)
    сверить_постановку(решение,выбор_постановки,пост)
    требовать(автор.проверить_токен(решение['модель']) and автор.проверить_токен(решение['усилие']),
        'неизвестные модель или усилие')
    return {'текст':приглашение(решение,выбор_постановки,основание),'модель':решение['модель'],
        'усилие':решение['усилие'],'источники':{'решение':сведения,'постановка':сведения_поста}}


def сверить_постановку(решение, выбор, пост):
    содержание,_,повреждение = этап.свежесть.split_recency_block(пост.decode())
    исходное,_,повреждение_исходного = этап.свежесть.split_recency_block(решение['постановка']['текст'])
    требовать(not повреждение and not повреждение_исходного and выбор['путь']==решение['постановка']['путь']
        and этап.свежесть.canonical_content(содержание)==этап.свежесть.canonical_content(исходное),
        'постановка отличается от сохранённого решения')


def нативная_привязка(решение, исполнитель, постановка, основание=None):
    поля(исполнитель, {'задача', 'корень', 'источник_модели'})
    идентификатор = обычное.идентичность(исполнитель['задача'])
    требовать(идентификатор != решение['координатор'], 'ROOT и исполнитель совпали')
    корень = этап.адреса.точный_абсолютный(исполнитель['корень'])
    требовать(гит(корень,'rev-parse','--show-toplevel') == str(корень), 'чужой native cwd')
    файл = этап.адреса.точный_абсолютный(исполнитель['источник_модели'])
    начало, контекст, граница = обычное.постановка.прочитать_начало_источника(файл)
    поручение = обычное.постановка.прочитать_нативное_поручение(файл, кодирование='буквальный')
    требовать(начало.get('id') == идентификатор and начало.get('thread_source') == 'agent_created_thread'
        and начало.get('cwd') == контекст.get('cwd') == str(корень), 'native UUID/cwd не совпали')
    требовать(начало.get('git',{}).get('commit_hash') == постановка['коммит'], 'неверная начальная база native')
    требовать(контекст.get('model') == решение['модель'] and контекст.get('effort') == решение['усилие'],
        'запрошенные модель/усилие не совпали с native')
    текст = приглашение(решение, постановка, основание)
    требовать(поручение['отправитель'] == решение['координатор'] and поручение['текст'] == текст,
        'неверное буквальное native-поручение')
    обычное.сверить_единый_снимок(файл, граница, поручение['источник'])
    return {'исполнитель': идентификатор, 'начало': граница, 'поручение': поручение['источник'],
        'хэш_нативного_поручения': хэш(текст.encode())}


def технические_входы(вход, решение, снимок, выбор, нативный):
    """Вывод технических полей, а не создание нового допуска."""
    дочерний = вход['фаза'] == 'входы'
    имя = 'исполнитель' if дочерний else 'корень'
    требовать(имя in решение['подготовка'], 'нет сохранённого recipe подготовки')
    р = решение['подготовка'][имя]
    поля(р, {'журнал','заголовок','описание','роль','цели','время','проверки','наполнение','предел_секунд'})
    поля(р['наполнение'], {'инструменты','профиль','поля','вставки'})

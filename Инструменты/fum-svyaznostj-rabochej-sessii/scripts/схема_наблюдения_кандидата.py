"""Закрытая форма сохранённого наблюдения; файловая система не читается."""
import os
from pathlib import PurePosixPath

from контракт_обратного_приёма import _ветка, _отпечаток, _поля, _текст


def проверить(значение, корень, глубина=0):
    if глубина >= 64:
        raise ValueError('Чрезмерная глубина наблюдения зависимостей')
    _поля(значение, 'корень коммит дерево ветка индекс_sha256 зависимости', 'наблюдение')
    путь = PurePosixPath(_текст(значение['корень'], 'корень наблюдения'))
    if (not путь.is_absolute() or str(путь) != значение['корень']
            or '..' in путь.parts or значение['корень'] != корень):
        raise ValueError('Неверный корень сохранённого наблюдения')
    _отпечаток(значение['коммит'], 40, 'коммит наблюдения')
    _отпечаток(значение['дерево'], 40, 'дерево наблюдения')
    _отпечаток(значение['индекс_sha256'], 64, 'индекс наблюдения')
    if значение['ветка'] is not None:
        _ветка({п: значение[п] for п in ('коммит', 'дерево', 'ветка')}, 'наблюдаемая ветка')
    зависимости = значение['зависимости']
    if type(зависимости) is not list:
        raise ValueError('Нужен полный список наблюдений зависимостей')
    предыдущее = None
    for зависимость in зависимости:
        _поля(зависимость, 'путь состояние', 'зависимость')
        имя = _текст(зависимость['путь'], 'путь зависимости')
        относительный = PurePosixPath(имя)
        сырые = os.fsencode(имя)
        if (относительный.is_absolute() or str(относительный) != имя
                or имя == '.' or any(п in ('..', '.git') for п in относительный.parts)
                or предыдущее is not None and сырые <= предыдущее):
            raise ValueError('Неверный или повторный путь зависимости')
        проверить(зависимость['состояние'], str(путь / относительный), глубина + 1)
        предыдущее = сырые

"""Типизированный адресный вход; полный допуск остаётся у создателя коммита."""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
import os
from pathlib import Path
import time

import создание_коммита as коммит
from готовность_этапа import список, точный_идентификатор


def точный_абсолютный(значение, *, приватный=False):
    текст = str(значение) if isinstance(значение, Path) else значение
    коммит.требовать(isinstance(текст, str) and текст == str(Path(текст).resolve()),
                    'нужно точное написание абсолютного физического пути')
    путь = коммит.путь(текст, приватный=приватный)
    предок = Path(путь.anchor)
    for часть in путь.parts[1:]:
        if предок.is_dir():
            имена = [э.name for э in предок.iterdir()]
            коммит.требовать(часть in имена or not any(э.casefold() == часть.casefold() for э in имена),
                            'неверный регистр абсолютного пути')
        предок /= часть
    return путь


@dataclass(frozen=True)
class ВходКонтрольнойТочки:
    подготовка: Path
    проверки: tuple[str, ...]

    def __post_init__(сам):
        список(list(сам.проверки) if isinstance(сам.проверки, tuple) else сам.проверки,
               точный_идентификатор)
        коммит.требовать(isinstance(сам.проверки, tuple), 'типизированный вход требует неизменный кортеж UUID')
        точный_абсолютный(сам.подготовка, приватный=True)

    @staticmethod
    def из_значений(подготовка, проверки):
        список(проверки, точный_идентификатор)
        return ВходКонтрольнойТочки(точный_абсолютный(подготовка, приватный=True), tuple(проверки))

    def готово(сам, предел, замены=None, *, доверенное_поручение=None):
        return коммит.объявить_готовность(сам.подготовка, list(сам.проверки), предел, замены,
                                        доверенное_поручение=доверенное_поручение)

    def создать(сам, *, доверенное_поручение=None):
        # Повтор сначала восстанавливает квитанцию. Живой gate находится внутри создателя.
        return коммит.создать(сам.подготовка, list(сам.проверки), доверенное_поручение=доверенное_поручение)


@dataclass(frozen=True)
class РаннийДопуск:
    индекс: str
    проверки: dict


def проверить_пути(параметры):
    корень = точный_абсолютный(параметры['корень'])
    for поле in ('подготовка', 'сообщение', 'квитанция', 'кэш_модели'):
        точный_абсолютный(параметры[поле], приватный=True)
    точный_абсолютный(параметры['источник_модели'])
    for источник in параметры['источники']:
        точный_абсолютный(источник['путь'])
        if 'кэш' in источник:
            точный_абсолютный(источник['кэш'], приватный=True)
    for поле in ('запрос', 'история_модели'):
        коммит.охват.точный_путь(корень, параметры[поле])
    коммит.разрешённые_цели(корень, параметры)
    return корень


def сверить_вход(файл_подготовки, необходимые, подготовка):
    вход = ВходКонтрольнойТочки.из_значений(файл_подготовки, необходимые)
    параметры = подготовка['параметры']
    коммит.требовать(параметры.get('режим') == 'контрольная-точка'
        and параметры.get('схема') in {'fum.создание-коммита.2', 'fum.создание-коммита.5',
                                     'fum.создание-коммита.6', 'fum.создание-коммита.7'},
        'фасад принимает существующие схемы контрольной точки')
    коммит.требовать(подготовка['схема'] == коммит.версия_подготовки(параметры),
                    'неверная версия подготовки контрольной точки')
    проверить_пути(параметры)
    коммит.требовать(str(вход.подготовка) == параметры['подготовка'], 'подменён путь подготовки')
    return вход


def ранний_допуск(корень, параметры, необходимые, подготовка, *, объявление=None):
    """Только чтение: индекс, существующие v4 и чистая политика поколений."""
    путь = коммит.готовность.путь_этапа(параметры)
    прежнее = коммит.готовность.прочитать(путь, параметры) if os.path.lexists(путь) else None
    if объявление is None and прежнее is not None:
        коммит.готовность.поколения.проверить_замены(
            прежнее['поколения'][-1]['снимок']['проверки'], необходимые, {})
    отпечаток = коммит.индекс(корень)
    допуск = коммит.проверки(корень, параметры, необходимые)
    if объявление is not None:
        предел, замены = объявление
        текущий = коммит.готовность.снимок(параметры, подготовка['команды'], необходимые, допуск)
        коммит.готовность.поколения.объявить(str(корень), текущий, допуск['свидетельства'],
                                          time.time_ns(), предел, прежнее=прежнее, замены=замены)
    return РаннийДопуск(отпечаток, допуск)


def первичная_сверка(параметры, номер):
    """Дешёвая первая проверка внутри настоящей активной обёртки, без готовности."""
    список([номер], точный_идентификатор)
    коммит.требовать(os.environ.get('FUM_CHECK_RUN_ID') == номер,
                    'первичная сверка требует UUID текущей отчётной обёртки')
    коммит.требовать(параметры.get('режим') == 'контрольная-точка'
        and параметры.get('схема') in {'fum.создание-коммита.2', 'fum.создание-коммита.5',
                                     'fum.создание-коммита.6', 'fum.создание-коммита.7'},
        'первичная сверка принимает контрольную точку')
    корень = проверить_пути(параметры)
    коммит.адрес(параметры)
    состав = коммит.проверить_ранний_состав(корень, параметры)
    _, _, _, каталог, сессия = коммит.отчёты.разрешить_сессию(корень, параметры['запрос'])
    коммит.отчёты.запретить_действие_при_возобновлении(каталог, 'первичная сверка')
    записи = коммит.отчёты.прочитать_историю_проверок(каталог, сессия)
    активные = [(путь, запись) for путь, запись, _ in записи if запись['состояние'] != 'завершён']
    коммит.требовать(len(активные) == 1 and активные[0][1]['идентификатор'] == номер
        and активные[0][1]['схема'] == 'fum.test-run.v4'
        and активные[0][1]['профиль_проверки']['класс'] == 'адресная',
        'нет единственного собственного адресного запуска v4')
    коммит.требовать(активные[0][0].relative_to(корень).as_posix() in параметры['разрешённые_цели'],
                    'текущая запись не включена в конечный состав')
    return {'схема': 'fum.первичная-сверка-контрольной-точки.1', 'предварительно_сверено': True,
            'проверка': номер, 'снимок': состав}


def главная(аргументы=None):
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    действия = разбор.add_subparsers(dest='действие', required=True)
    первый = действия.add_parser('первичная-сверка', allow_abbrev=False)
    первый.add_argument('--вход', required=True)
    первый.add_argument('--проверка', required=True)
    for имя in ('готово', 'создать'):
        команда = действия.add_parser(имя, allow_abbrev=False)
        команда.add_argument('--подготовка', required=True)
        команда.add_argument('--проверка', action='append', required=True)
        команда.add_argument('--выбранное-поручение')
        if имя == 'готово':
            команда.add_argument('--предел-секунд', type=int, required=True)
    п = разбор.parse_args(аргументы)
    try:
        if п.действие == 'первичная-сверка':
            файл = точный_абсолютный(п.вход, приватный=True)
            параметры = коммит.сообщения._разобрать(коммит.прочитать(файл, приватный=True))
            итог = первичная_сверка(параметры, п.проверка)
        else:
            вход = ВходКонтрольнойТочки.из_значений(п.подготовка, п.проверка)
            выбор = None if п.выбранное_поручение is None else коммит.сообщения._разобрать(
                коммит.прочитать(точный_абсолютный(п.выбранное_поручение, приватный=True), приватный=True))
            итог = (вход.готово(п.предел_секунд, доверенное_поручение=выбор) if п.действие == 'готово'
                    else вход.создать(доверенное_поручение=выбор))
        print(json.dumps(итог, ensure_ascii=False, sort_keys=True))
        return 0
    except (OSError, ValueError, KeyError, TypeError, коммит.отчёты.ОшибкаОтчёта) as ошибка:
        print(str(ошибка), file=__import__('sys').stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(главная())

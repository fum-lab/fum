"""Явный локальный вход ROOT; построение команды не выдаёт приёмку или READY."""
from pathlib import Path
import stat


def команда(корень, интерпретатор, действие, аргументы):
    """Сохраняет аргументы штатного CLI и не ищет запасной старый контур."""
    имена = {
        'подготовить': 'создание_коммита.py',
        'подготовить-повтор': 'создание_коммита.py',
        'первичная-сверка': 'типизированная_контрольная_точка.py',
        'готово': 'типизированная_контрольная_точка.py',
        'создать': 'типизированная_контрольная_точка.py',
    }
    if действие not in имена:
        raise ValueError('неизвестная локальная операция Creator')
    корень = Path(корень)
    if not корень.is_absolute() or корень.resolve() != корень or not корень.is_dir():
        raise ValueError('нужен точный физический корень текущего checkout')
    путь = корень
    try:
        for часть in ('Инструменты', 'fum-svyaznostj-rabochej-sessii', 'scripts', имена[действие]):
            путь = путь / часть
            режим = путь.lstat().st_mode
            if stat.S_ISLNK(режим):
                raise ValueError('ссылка не выбирает локальный проверяющий')
            if часть == имена[действие]:
                if not stat.S_ISREG(режим):
                    raise ValueError('локальный вход не является обычным файлом')
            elif not stat.S_ISDIR(режим):
                raise ValueError('предок локального входа не является каталогом')
    except OSError as ошибка:
        raise ValueError('локальный вход недоступен; возврат к старому контуру запрещён') from ошибка
    if not isinstance(интерпретатор, str) or not Path(интерпретатор).is_absolute():
        raise ValueError('нужен явно выбранный абсолютный путь интерпретатора')
    if not isinstance(аргументы, (list, tuple)) or any(
            not isinstance(a, str) or '\0' in a for a in аргументы):
        raise ValueError('аргументы CLI должны быть последовательностью строк')
    return [интерпретатор, '-E', '-s', '-S', '-B', str(путь), действие, *аргументы]

def обернуть(команда):
    """Явная передача независимого выбора только известному дочернему CLI."""
    if not активен():
        return команда
    позиция_скрипта = next((позиция for позиция, аргумент in enumerate(команда) if аргумент in {
        str(путь_входа) for путь_входа, _ in _входы().values()}), None)
    if позиция_скрипта is None:
        return команда
    требовать(позиция_скрипта >= 1 and all(разобранное in {'-E', '-s', '-S', '-B'} for разобранное in команда[1:позиция_скрипта]),
        'неизвестная команда передачи назначения этапа')
    имя_входа = next(ключ_входа for ключ_входа, (путь_входа, _) in _входы().items() if str(путь_входа) == команда[позиция_скрипта])
    if имя_входа == 'pair' and (len(команда) == позиция_скрипта + 1 or команда[позиция_скрипта + 1] not in {
            'обычная-пара-план', 'обычная-пара-установить'}):
        # Filler .1 сохраняет своё прежнее замыкание импортов. Внешний фасад
        # повторяет назначение этапа на границах этого эффекта.
        return команда
    пин_назначения = пин_выбора()
    return [команда[0], '-E', '-s', '-S', '-B', str(Path(__file__).resolve()),
        '--выбор', пин_назначения['путь'], '--контур', имя_входа, '--', *команда[позиция_скрипта + 1:]]


def главная(аргументы=None):
    import argparse
    import importlib.util
    разборщик = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разборщик.add_argument('--выбор', required=True)
    разборщик.add_argument('--контур', required=True, choices=tuple(_входы()))
    разборщик.add_argument('аргументы', nargs=argparse.REMAINDER)
    разобранное = разборщик.parse_args(аргументы)
    требовать(разобранное.аргументы and разобранное.аргументы[0] == '--', 'нужна явная граница аргументов CLI')
    требовать(разобранное.контур != 'pair' or len(разобранное.аргументы) > 1 and разобранное.аргументы[1] in {
        'обычная-пара-план', 'обычная-пара-установить'}, 'прежний filler не является stage CLI')
    from подготовка_этапа_коммита import _прочитать_приватный_объект

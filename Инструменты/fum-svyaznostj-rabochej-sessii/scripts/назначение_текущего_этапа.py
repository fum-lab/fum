"""Явно выбранный ROOT этап; прежний ACT и настоящее рождение неизменяемы.

Контекст существует только в текущем Python-вызове. Копия selector в maker,
переменная среды или сохранённая подготовка не создают независимый выбор.
"""
from contextlib import contextmanager
from contextvars import ContextVar
import copy
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()

СХЕМА = 'fum.назначение-текущего-этапа.1'
ПРИВЯЗКА = 'fum.привязка-текущего-этапа.1'
_ВЫБОР = ContextVar('fum.независимый-выбор-текущего-этапа.1', default=None)
ПОЛЯ = {'схема', 'этап', 'координатор', 'исполнитель', 'ветка',
    'физический_корень_sha256', 'база', 'постановка', 'область', 'цели',
    'план_пары_sha256', 'нативное_начало', 'нативное_поручение', 'команды_этапа'}
ПОЛЯ_ПРИВЯЗКИ = {'схема', 'выбор', 'база', 'ветка', 'физический_корень_sha256',
    'цели', 'план_пары_sha256', 'нативное_начало', 'нативное_поручение', 'команды_этапа', 'код_sha256'}


def _обычный():
    import обычное_поручение
    return обычное_поручение


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def _хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def _байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2,
        allow_nan=False) + '\n').encode()


def _проверить_хэш_назначения(значение):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение),
        'неверный SHA256 назначения этапа')


@contextmanager
def выбрать(выбор, *, файл=None):
    """Только внешний адресный вход; выбор не выводится из maker или окружения."""
    _обычный().выбор(выбор)
    требовать(_ВЫБОР.get() is None, 'вложенная замена назначения этапа запрещена')
    токен = _ВЫБОР.set((copy.deepcopy(выбор), файл))
    try:
        yield
    finally:
        _ВЫБОР.reset(токен)


def активен():
    return _ВЫБОР.get() is not None


def прочитать(корень, выбор):
    """Читает настоящий новый документ; никогда не переименовывает его в ACT."""
    требовать(_хэш(Path(__file__).read_bytes()) == КОД_ПРИ_ЗАГРУЗКЕ,
        'исполняемый код назначения этапа изменился после загрузки')
    текущий = _ВЫБОР.get()
    требовать(текущий is not None and текущий[0] == выбор,
        'нет независимого внешнего выбора текущего этапа')
    м = _обычный(); м.выбор(выбор)
    if текущий[1] is not None:
        from подготовка_этапа_коммита import _прочитать_приватный_объект
        значение, _ = _прочитать_приватный_объект(текущий[1])
        требовать(значение == выбор, 'файл внешнего выбора этапа изменился')
    м.путь(корень, выбор['путь'])
    запись = м._гит(корень, 'ls-tree', '-z', выбор['коммит'], '--', ':(literal)' + выбор['путь'])
    части = запись.split('\0')
    требовать(len(части) == 2 and части[1] == '' and '\t' in части[0],
        'нет точного Git-файла назначения этапа')
    заголовок, имя = части[0].split('\t')
    требовать(имя == выбор['путь'] and заголовок.split()[:2] == ['100644', 'blob'],
        'назначению этапа нужен Git100644 blob')
    данные = м.делегация.сверить_источник(корень, выбор)
    документ = м.контракт.разобрать_байты(данные)
    м.контракт.поля(документ, ПОЛЯ)
    требовать(документ['схема'] == СХЕМА, 'неверная схема текущего этапа')
    требовать(type(документ['этап']) is str and re.fullmatch(r'[^\s/]+-v[1-9][0-9]*', документ['этап']),
        'нужен конечный версионный идентификатор этапа')
    for к in ('координатор', 'исполнитель'):
        требовать(документ[к] == выбор[к], 'подменён UUID назначения этапа')
    м.контракт.поля(документ['база'], {'коммит', 'дерево'})
    for идентификатор_коммита in документ['база'].values():
        м.история.полный_идентификатор(идентификатор_коммита)
    for к in ('физический_корень_sha256', 'план_пары_sha256'):
        _проверить_хэш_назначения(документ[к])
    м.выбор({**документ['постановка'], 'координатор': выбор['координатор'],
        'исполнитель': выбор['исполнитель']})
    м.делегация.сверить_источник(корень, документ['постановка'])
    требовать(документ['постановка']['коммит'] == документ['база']['коммит'],
        'постановка не относится к точной основе этапа')
    return документ


def _адрес(корень, документ, *, новый_эффект):
    м = _обычный()
    требовать(type(корень) is Path or isinstance(корень, Path), 'нужен физический W этапа')
    требовать(корень.is_absolute() and корень.resolve() == корень
        and м._гит(корень, 'rev-parse', '--show-toplevel') == str(корень)
        and _хэш(str(корень).encode()) == документ['физический_корень_sha256'],
        'чужой физический W текущего этапа')
    запрещены = {'GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR',
        'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES', 'GIT_CONFIG_PARAMETERS',
        'GIT_CONFIG_COUNT', 'GIT_REPLACE_REF_BASE', 'GIT_SHALLOW_FILE', 'GIT_NAMESPACE'}
    требовать(not запрещены.intersection(os.environ), 'перенаправление Git этапа запрещено')
    ветка = документ['ветка']
    требовать(type(ветка) is str and ветка.startswith('refs/heads/'), 'нужен полный ref этапа')
    м._гит(корень, 'check-ref-format', ветка)
    требовать(м._гит(корень, 'symbolic-ref', '-q', 'HEAD') == ветка,
        'не совпадает точный назначенный ref')
    владельцы = [б for б in м._гит(корень, 'worktree', 'list', '--porcelain').split('\n\n')
        if 'branch ' + ветка in б.splitlines()]
    требовать(len(владельцы) == 1 and владельцы[0].splitlines()[0] == 'worktree ' + str(корень),
        'назначенная ветка занята другим деревом')
    база = документ['база']
    требовать(м._гит(корень, 'rev-parse', база['коммит'] + '^{commit}') == база['коммит']
        and м._гит(корень, 'rev-parse', база['коммит'] + '^{tree}') == база['дерево'],
        'дрейф точных C/T этапа')
    if новый_эффект:
        требовать(м._гит(корень, 'rev-parse', 'HEAD') == база['коммит'], 'HEAD этапа изменился')


def _нативное(параметры, документ):
    м = _обычный(); источник = Path(параметры['источник_модели'])
    требовать(источник.is_absolute() and источник.resolve() == источник,
        'нужен настоящий физический native JSONL')
    до = источник.stat()
    требовать(stat.S_ISREG(до.st_mode), 'native JSONL не является обычным файлом')
    начало, контекст, граница = м.постановка.прочитать_начало_источника(источник)
    м.контракт.поля(документ['нативное_начало'], {'коммит', 'граница', 'sha256'})
    рождение = документ['нативное_начало']
    м.история.полный_идентификатор(рождение['коммит'])
    требовать(начало.get('id') == документ['исполнитель']
        and начало.get('thread_source') == 'agent_created_thread'
        and начало.get('cwd') == контекст.get('cwd') == параметры['корень']
        and начало.get('git', {}).get('commit_hash') == рождение['коммит']
        and граница == {к: рождение[к] for к in ('граница', 'sha256')},
        'подменено настоящее нативное рождение')
    поручение = м.постановка.прочитать_нативное_поручение(источник, кодирование='буквальный')
    н = документ['нативное_поручение']
    м.контракт.поля(н, {'граница', 'sha256', 'sha256_текста'})
    требовать(поручение['отправитель'] == документ['координатор']
        and поручение['источник'] == {к: н[к] for к in ('граница', 'sha256')}
        and _хэш(поручение['текст'].encode()) == н['sha256_текста'],
        'подменено первоначальное нативное поручение')
    команды = документ['команды_этапа']
    требовать(type(команды) is list and 1 <= len(команды) <= 2048,
        'нужен конечный упорядоченный набор агентских команд')
    конец = н['граница']; объём = 0; результат = []; прочитанные = []
    with источник.open('rb') as поток:
        for адресное in команды:
            м.контракт.поля(адресное, {'начало', 'конец', 'sha256', 'sha256_текста'})
            а, б = адресное['начало'], адресное['конец']
            требовать(type(а) is int and type(б) is int and конец <= а < б <= до.st_size
                and б - а <= 16 * 1024 * 1024, 'неверный диапазон или порядок агентских команд')
            объём += б - а
            требовать(объём <= 16 * 1024 * 1024, 'превышен конечный объём команд этапа')
            поток.seek(а - 1); требовать(поток.read(1) == b'\n', 'диапазон начинается внутри строки')
            поток.seek(а); сырые = поток.read(б - а)
            требовать(сырые.endswith(b'\n') and сырые.count(b'\n') == 1
                and _хэш(сырые) == адресное['sha256'], 'подмена RAW агентской команды')
            запись = м.контракт.разобрать_байты(сырые)
            требовать(type(запись) is dict and type(запись.get('payload')) is dict,
                'неверная структура нативной агентской команды')
            нагрузка = запись['payload']
            требовать(запись.get('type') == 'response_item' and нагрузка.get('type') == 'function_call_output'
                and нагрузка.get('name') == 'send_message_to_thread'
                and нагрузка.get('namespace') == 'codex_app', 'неверный нативный транспорт этапа')
            транспорт = re.fullmatch(r'<codex_delegation>\n  <source_thread_id>([^<\n]+)</source_thread_id>\n  <input>(.*)</input>\n</codex_delegation>',
                нагрузка.get('output', ''), re.S)
            требовать(транспорт is not None and транспорт[1] == документ['координатор']
                and _хэш(транспорт[2].encode()) == адресное['sha256_текста'], 'чужая агентская команда ROOT')
            экземпляр = _хэш(_байты({'задача': документ['координатор'],
                'исполнитель': документ['исполнитель'], 'позиция': адресное}))
            результат.append({'задача': документ['координатор'], 'экземпляр': экземпляр,
                'позиция': {к: адресное[к] for к in ('начало', 'конец', 'sha256')},
                'текст': транспорт[2], 'происхождение': 'агентское-поручение-ROOT'})
            прочитанные.append((а, сырые)); конец = б
    м.сверить_единый_снимок(источник, граница, поручение['источник'])
    после = источник.stat()
    требовать((до.st_dev, до.st_ino) == (после.st_dev, после.st_ino) and после.st_size >= конец,
        'native JSONL подменён после проверки')
    with источник.open('rb') as поток:
        for а, сырые in прочитанные:
            поток.seek(а); требовать(поток.read(len(сырые)) == сырые, 'агентская команда изменилась')
    return граница, поручение['источник'], результат


def _проверить(параметры, выбор, *, новый_эффект=True):
    """Повторно читает G и реальные границы; не создаёт эффектов или READY."""
    требовать(type(параметры) is dict and параметры.get('схема') == 'fum.создание-коммита.10'
        and параметры.get('режим') == 'контрольная-точка', 'этап требует обычный закрытый maker')
    м = _обычный(); корень = Path(параметры['корень'])
    документ = прочитать(корень, выбор)
    требовать(параметры.get('выбранное_поручение') == выбор
        and параметры['задача'] == документ['координатор']
        and параметры['исполнитель'] == документ['исполнитель'] == os.environ.get('CODEX_THREAD_ID')
        and параметры['ветка'] == документ['ветка']
        and параметры['исходный_коммит'] == документ['база']['коммит'],
        'чужие UUID/ref/C текущего этапа')
    _адрес(корень, документ, новый_эффект=новый_эффект)
    цели = документ['цели']
    требовать(type(цели) is list and цели and len(цели) == len(set(цели))
        and параметры['разрешённые_цели'] == цели, 'изменились точные упорядоченные цели этапа')
    запрос = параметры['запрос']; история = параметры['история_модели']
    требовать(type(запрос) is str and м.охват.СВЯЗНОСТЬ.is_request_file(корень / запрос, корень)
        and type(история) is str and история.startswith(str(Path(запрос).parent / 'материалы') + '/'),
        'чужая собственная пара или модель этапа')
    м.проверить_область(корень, документ['область'], [*цели, запрос,
        str(Path(запрос).with_name('отчёт.md')), история])
    if параметры['схема'] == 'fum.создание-коммита.10':
        план = параметры['контракт_журнала']['открытая']
        требовать(_хэш(_байты(план)) == документ['план_пары_sha256']
            and план['основание'] == документ['постановка']
            and запрос == '/'.join(('Журнал', план['журнал'], 'запрос.md')), 'изменился план собственной пары')
    рождение, приглашение, команды = _нативное(параметры, документ)
    м._гит(корень, 'merge-base', '--is-ancestor', документ['нативное_начало']['коммит'], документ['база']['коммит'])
    результат = {к: copy.deepcopy(документ[к]) for к in ПОЛЯ_ПРИВЯЗКИ - {'схема', 'выбор', 'код_sha256'}}
    результат.update(схема=ПРИВЯЗКА, выбор=copy.deepcopy(выбор), код_sha256=КОД_ПРИ_ЗАГРУЗКЕ)
    return результат, команды


def проверить(параметры, выбор, *, новый_эффект=True):
    return _проверить(параметры, выбор, новый_эффект=новый_эффект)[0]


def команды(параметры):
    требовать(активен(), 'нет внешнего выбора агентских команд')
    return _проверить(параметры, _ВЫБОР.get()[0], новый_эффект=False)[1]


def проверить_адрес(параметры, *, новый_эффект=False):
    требовать(активен(), 'нет внешнего назначения точного ref')
    return проверить(параметры, _ВЫБОР.get()[0], новый_эффект=новый_эффект)


def проверить_привязку(параметры, привязка):
    требовать(type(привязка) is dict and set(привязка) == ПОЛЯ_ПРИВЯЗКИ
        and привязка['схема'] == ПРИВЯЗКА, 'неверная версионная привязка этапа')
    # Историческая готовность связывает C/T, а HEAD уже может быть результатом.
    требовать(проверить(параметры, привязка['выбор'], новый_эффект=False) == привязка,
        'назначение этапа изменилось после подготовки')


def проверить_ветку(корень, коммит, ветка):
    требовать(активен(), 'нет внешнего назначения ref ребёнка')
    д = прочитать(корень, _ВЫБОР.get()[0])
    требовать(д['база']['коммит'] == коммит and д['ветка'] == ветка,
        'чужая основа виртуального Журнала этапа')
    _адрес(корень, д, новый_эффект=True)


def пин_выбора():
    текущий = _ВЫБОР.get()
    требовать(текущий is not None and текущий[1] is not None,
        'подпроцесс требует внешний физический файл выбора этапа')
    from подготовка_этапа_коммита import _прочитать_приватный_объект
    значение, пин = _прочитать_приватный_объект(текущий[1])
    требовать(значение == текущий[0], 'внешний выбор этапа изменился')
    return пин



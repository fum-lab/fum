"""Исторический native ROOT и действующий адрес его постоянной ветки."""
import hashlib
import importlib.util
from pathlib import Path
import re
import sys


ROOT_FUMA = '01a07d3d-d376-7ad2-aafc-67e4c25a67eb'
ПРАВИЛО = 'FUM-ПРАВИЛО-000121'
ТЕМА = 'Правила/агентов/журнал-и-происхождение.md'
ИНВЕНТАРЬ = 'Правила/агентов/инвентарь-правил.json'
# Весь известный блок нормы, включая ограничения; знакомый префикс
# с дописанной отменой не разрешает прежнее исключение.
ПРОФИЛЬ_НОРМЫ = 'e50762c40d6f95b0bb6995307a9abb531b911a0d16d64b5a0af44ecc9499a82a'
ВАЛИДАТОР_ПРАВИЛ = None


def требовать(условие, сообщение):
    if not условие: raise ValueError(сообщение)


def контур_правил():
    global ВАЛИДАТОР_ПРАВИЛ
    if ВАЛИДАТОР_ПРАВИЛ is not None: return ВАЛИДАТОР_ПРАВИЛ
    имя = 'правила_происхождения_писателя'
    файл = Path(__file__).resolve().parents[2]/'fum-dekompoziciya-pravil-agentov/scripts/проверить-декомпозицию-правил.py'
    описание = importlib.util.spec_from_file_location(имя,файл)
    модуль = importlib.util.module_from_spec(описание)
    прежние = list(sys.path)
    try:
        sys.path.insert(0,str(файл.parent)); описание.loader.exec_module(модуль)
    finally: sys.path[:] = прежние
    sys.modules[имя] = модуль
    # Глобальная ссылка делает исполняемый валидатор и оба импортированных
    # checker-модуля достижимыми для штатного обхода closure композиции.
    ВАЛИДАТОР_ПРАВИЛ = модуль
    return модуль


def основание_переноса(корень):
    """Строгая привязка к активной декларации, а не новое разрешение по UUID."""
    м = контур_правил()
    try:
        инвентарь = м.проверить_точный_локальный_путь(корень,ИНВЕНТАРЬ)
        данные = м.прочитать_инвентарь(инвентарь)
        м.проверить_структуру(корень,данные)
        правила = [п for п in данные['правила'] if п['идентификатор']==ПРАВИЛО]
        требовать(len(правила)==1 and правила[0]['статус']=='действует'
            and правила[0]['приоритет']=='P2-тема'
            and правила[0]['назначение']=={'путь':ТЕМА,'якорь':ПРАВИЛО},
            'нет действующего исключения переноса ROOT')
        тема = м.проверить_точный_локальный_путь(корень,ТЕМА)
        текст = тема.read_text(encoding='utf-8')
        якоря = list(re.finditer(r'^<!-- FUM-ПРАВИЛО: ([^\n]+) -->\n',текст,re.MULTILINE))
        номера = [н for н,я in enumerate(якоря) if я.group(1)==ПРАВИЛО]
        требовать(len(номера)==1,'неоднозначное основание переноса ROOT')
        н = номера[0]; конец = якоря[н+1].start() if н+1<len(якоря) else len(текст)
        тело = текст[якоря[н].end():конец]
        требовать(hashlib.sha256(тело.encode('utf-8')).hexdigest()==ПРОФИЛЬ_НОРМЫ,
            'неизвестная декларация переноса ROOT')
        пути = {'AGENTS.md',ИНВЕНТАРЬ,*[т['путь'] for т in данные['темы']],
            *данные['служебные_пути_изменения_правил'],
            *[п['новое_основание'] for п in данные['правила'] if not п['источники']],
            данные['продолжение_задачи']['сценарий'],
            данные['продолжение_задачи']['остаток_сообщений']['сценарий']}
        for имя in ('дочерняя_передача','дочерний_приём'):
            пути.update(з for з in данные[имя].values() if isinstance(з,str) and з.startswith('Инструменты/'))
        входы = {п:hashlib.sha256(м.проверить_точный_локальный_путь(корень,п).read_bytes()).hexdigest()
            for п in sorted(пути)}
        return {'правило':ПРАВИЛО,'входы':входы}
    except (м.ОшибкаПроверки,KeyError,TypeError,OSError) as ошибка:
        raise ValueError('непроверенное основание переноса ROOT: '+str(ошибка)) from ошибка


def проверить(вход, решение, снимок, начало, контекст, корень):
    требовать(начало.get('id')==вход['писатель']
        and type(начало.get('cwd')) is str and начало['cwd']
        and начало['cwd']==контекст.get('cwd')
        and all(type(контекст.get(к)) is str and контекст[к] for к in ('model','effort')),
        'неполное наблюдение модели писателя')
    if контекст['cwd']==str(корень): return None
    state = вход.get('схема') == 'fum.подготовка-дочернего-поручения.6'
    state = state and решение.get('схема') == 'fum.смысл-дочернего-поручения.4' and вход['фаза'] == 'полномочия'
    требовать(вход['писатель']==решение['координатор']==ROOT_FUMA
        and (вход['фаза'] in {'постановка','акт'} or state) and снимок['ref']=='refs/heads/fuma',
        'исторический cwd не разрешает перенос этого писателя')
    return основание_переноса(корень)

import copy
from pathlib import Path
import time

import план_журнала_писателя_состояния as прежний
import проверенный_план_журнала_состояния as проверка
import каркас_журнала_состояния as каркас
import исторические_байты_ожиданий as исторические

гит = прежний.гит
требовать = прежний.требовать
поля = прежний.полномочия.поля
хэш = прежний.хэш
читатель = прежний.читатель
ИД = прежний.полномочия.ИДЕНТИЧНОСТЬ
ТЕМА = 'Инструменты/fum-svyaznostj-rabochej-sessii/'
РЕСУРСЫ = ('scripts/независимая_пара_журнала.py', 'scripts/контракт_независимого_журнала.py',
    'scripts/каркас_журнала_состояния.py')


def _blob(корень, коммит, путь):
    читатель.канон.источник({'коммит': коммит, 'путь': путь, 'sha256': '0'*64})
    гит.полный_объект(корень, коммит)
    записи = гит.выполнить(корень, 'ls-tree', '-z', коммит, '--', путь).stdout.split(b'\0')
    записи = [э for э in записи if э]
    требовать(len(записи) == 1 and записи[0].split(b'\t')[1] == путь.encode()
        and записи[0].split(b' ', 2)[:2] == [b'100644', b'blob'], 'нужен точный blob 0644')
    размер = int(гит.гит(корень, 'cat-file', '-s', коммит+':'+путь))
    требовать(0 < размер <= читатель.ПРЕДЕЛ, 'Git blob превышает границу чтения')
    данные = гит.объект_файла(корень, коммит, путь)
    требовать(len(данные) == размер, 'размер Git blob разошёлся')
    return данные


def _доверие(корень, доверие, H):
    поля(доверие, {'схема', 'ref', 'источник'} | ИД)
    требовать(доверие['схема'] == 'fum.доверие-ожиданиям-узла.1'
        and доверие['ref'] == прежний.полномочия.ВЕТКА, 'неизвестное доверие или ref')
    for ключ in ИД: прежний.полномочия.строка(доверие[ключ])
    for ключ in ('координатор', 'владелец'): прежний.полномочия.идентификатор(доверие[ключ])
    требовать(доверие['координатор'] != доверие['владелец'], 'ROOT не является своим писателем')
    выбор = доверие['источник']; читатель.канон.источник(выбор)
    R = гит.полный_объект(корень, выбор['коммит']); гит.полный_объект(корень, H)
    требовать(гит.предок(корень, R, H), 'R должен быть предком H')
    данные = _blob(корень, R, выбор['путь'])
    требовать(хэш(данные) == выбор['sha256'] and _blob(корень, H, выбор['путь']) == данные,
        'ожидания R изменились в H')
    return исторические.проверить(данные, доверие, корень=корень)


def _отсутствие(корень, H, журнал, *, живой):
    ключ = каркас.контракт.ключ_коллизии
    записи = гит.выполнить(корень, 'ls-tree', '-z', H+':Журнал').stdout.split(b'\0')
    требовать(not any(ключ(э.split(b'\t', 1)[1].decode()) == ключ(журнал)
        for э in записи if b'\t' in э), 'новая папка или её двойник уже в H')
    if not живой: return
    родитель = корень/'Журнал'
    требовать(родитель.is_dir() and not родитель.is_symlink(), 'нужен обычный Журнал')
    требовать(not any(ключ(п.name) == ключ(журнал) for п in родитель.iterdir()),
        'новая папка или её двойник уже в checkout')
    адрес = ключ('Журнал/'+журнал)
    записи = гит.выполнить(корень, 'ls-files', '-z').stdout.split(b'\0')
    требовать(not any(э and (ключ(э.decode()) == адрес or ключ(э.decode()).startswith(адрес+'/'))
        for э in записи), 'новая папка или её двойник уже в индексе')


def _ресурсы(корень, H, выбор=None):
    if выбор is not None:
        требовать(type(выбор) is list and len(выбор) == len(РЕСУРСЫ), 'неверный состав строителя')
    итог = []
    for номер, путь in enumerate(РЕСУРСЫ):
        данные = _blob(корень, H, ТЕМА+путь)
        ресурс = {'коммит': H, 'путь': ТЕМА+путь, 'sha256': хэш(данные)}
        требовать(данные == читатель.прочитать_файл(Path(__file__).parent/Path(путь).name,
            предел=читатель.ПРЕДЕЛ), 'исполняемый строитель отличается от H')
        if выбор is not None: требовать(выбор[номер] == ресурс, 'подмена строителя или порядка ресурсов')
        итог.append(ресурс)
    return итог


def _построить(вход, *, корень, профиль):
    начало = time.monotonic_ns()
    поля(вход, {'схема', 'доверие', 'исходный_коммит', 'хэш_корня', 'время', 'метка',
        'первоначальный_запрос', 'предыдущий_этап', 'источники'})
    требовать(вход['схема'] == 'fum.вход-плана-журнала-писателя-состояния.2', 'неизвестный вход P.2')
    корень = гит.физический_корень(корень); до = прежний._состояние(корень)
    H = вход['исходный_коммит']; доверие = copy.deepcopy(вход['доверие'])
    требовать(вход['хэш_корня'] == хэш(str(корень).encode())
        and до[:2] == (H, прежний.полномочия.ВЕТКА), 'чужой корень или неактуальный H/ref')
    _доверие(корень, доверие, H); после_доверия = time.monotonic_ns()
    prefix, label = прежний.генератор.разобрать_время(вход['время'])
    метка = вход['метка']; прежний.этап.каркас._проверить_метку_сессии(метка)
    журнал = prefix+'_'+метка; каркас.контракт.имя_журнала(журнал)
    _отсутствие(корень, H, журнал, живой=True)
    for ключ in ('первоначальный_запрос', 'предыдущий_этап'):
        прежний._история(корень, вход[ключ], H, доверие['координатор'])
    источники = вход['источники']
    требовать(type(источники) is list and 1 <= len(источники) <= 16
        and all(type(э) is dict and э.get('задача') == доверие['координатор']
            and type(э.get('экземпляры')) is list and 1 <= len(э['экземпляры']) <= 128
            for э in источники), 'неверный конечный выбор команд ROOT')
    команды = прежний.этап.корневые_команды({'корень': str(корень), 'источники': источники})
    п = {'схема': 'fum.план-журнала-писателя-состояния.2', **{к: доверие[к] for к in ИД},
        'ветка': доверие['ref'], 'исходный_коммит': H, 'доверие': доверие,
        'хэш_корня': вход['хэш_корня'], 'журнал': журнал, 'метка': метка,
        'заголовок': прежний.этап.каркас._заголовок_из_метки(метка), 'время': вход['время'],
        'происхождение_времени': 'Получено get-session-time.py --format both: '+prefix+'; '+label+'. Время сохранённого плана.',
        'первоначальный_запрос': copy.deepcopy(вход['первоначальный_запрос']),
        'предыдущий_этап': copy.deepcopy(вход['предыдущий_этап']), 'команды': команды,
        'источники_команд': [{'задача': э['задача'], 'граница_снимка': copy.deepcopy(э['граница_снимка']),
            'экземпляры': list(э['экземпляры'])} for э in источники], 'строитель': _ресурсы(корень, H)}
    проверка._команды(п); после_источников = time.monotonic_ns()
    п['идентификатор'], п['файлы'] = каркас.рассчитать(п)
    _ресурсы(корень, H, п['строитель']); _отсутствие(корень, H, журнал, живой=True)
    требовать(прежний._состояние(корень) == до, 'изменились HEAD/ref/индекс при построении')
    данные = читатель.кодировать(п); требовать(len(данные) <= читатель.ПРЕДЕЛ, 'P.2 превышает границу')
    if профиль is not None:
        профиль.update({'доверие_наносекунды': после_доверия-начало,
            'источники_наносекунды': после_источников-после_доверия,
            'каркас_и_повтор_наносекунды': time.monotonic_ns()-после_источников,
            'всего_наносекунды': time.monotonic_ns()-начало, 'команд': len(команды), 'API': 0})
    return {'байты': данные, 'sha256': хэш(данные), 'разрешение_установки': False}


def построить(вход, *, корень, профиль=None):
    try: return _построить(вход, корень=корень, профиль=профиль)
    except (читатель.канон.приём_делегации.гит.ОшибкаОтчёта, прежний.этап.каркас.LayoutError,
            KeyError, TypeError, UnicodeError) as ошибка:
        raise ValueError(str(ошибка)) from ошибка

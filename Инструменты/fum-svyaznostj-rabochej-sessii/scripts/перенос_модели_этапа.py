"""Ограниченная композиция штатного переноса и адресного восстановления."""
import argparse
import os
from pathlib import Path
import re
import sys

import автор_коммита as автор
import перенести_историю_модели as перенос

модель = перенос.модель
чтение = модель.чтение
требовать = чтение._требовать
байты = чтение._байты
хэш = чтение._хэш
ИНСТРУМЕНТЫ = Path(__file__).resolve().parents[2]


def снимок(путь):
    """SHA и метка обычного файла, прочитанного без следования symlink."""
    ф = модель._путь(путь)
    with os.fdopen(os.open(ф, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno()); чтение._обычный(до)
        д = поток.read(); после = os.fstat(поток.fileno())
    требовать(чтение._метка(до) == чтение._метка(после) == чтение._метка(ф.stat()),
        'дрейф прочитанного файла переноса')
    return {'путь': str(ф), 'sha256': хэш(д), 'метка': чтение._метка(до)}


def замыкание_кода():
    """Полное конечное замыкание загруженных предметных импортов, включая reader."""
    import подготовка_этапа_коммита as этап
    очередь = [sys.modules[__name__], перенос, автор, этап]; найденные = set()
    while очередь:
        м = очередь.pop(); имя = getattr(м, '__file__', None)
        if type(имя) is not str:
            continue
        ф = Path(имя).absolute()
        if not ф.is_relative_to(ИНСТРУМЕНТЫ) or 'tests' in ф.relative_to(ИНСТРУМЕНТЫ).parts or ф in найденные:
            continue
        найденные.add(ф)
        for з in vars(м).values():
            связанный = з if type(з) is type(sys) else sys.modules.get(getattr(з, '__module__', '')) if callable(з) else None
            if связанный is not None:
                очередь.append(связанный)
    # validate_layout штатно загружает этот модуль позднее при prepare.
    # Его байты включены до первого эффекта независимо от состояния sys.modules.
    найденные.add(ИНСТРУМЕНТЫ/'fum-pereimenovaniye-fajla-s-obnovleniyem-ssyilok/scripts/pereimenovatj-fajl-s-obnovleniyem-ssyilok.py')
    return [снимок(ф) for ф in sorted(найденные)]


def назначения(п):
    требовать(п.get('схема') == 'fum.создание-коммита.5' and п.get('режим') == 'контрольная-точка',
        'перенос принимает только обычный ROOT .5')
    корень = модель._путь(п['корень'])
    и, к, н = map(модель._путь, (п['источник_модели'], п['кэш_модели'], корень/п['история_модели']))
    требовать(н.is_relative_to(корень), 'новая история вне своего checkout')
    требовать(not к.is_relative_to(корень) and not any(os.path.lexists(р/'.git') for р in к.parents),
        'новый курсор должен быть вне Git')
    чтение._обычный(и.stat())
    return корень, и, к, н


def проверить_модель(п, результат):
    требовать(результат['полнота'], 'перенос модели неполон; prepare запрещён')
    return автор.составить_имя(п['имя_автора'], результат['последнее'])


def _предварить(п, т, *, новые_отсутствуют):
    требовать(type(т) is dict and set(т) == {'прежняя_история', 'прежний_кэш'}, 'неверные поля переноса модели')
    корень, источник, кэш, история = назначения(п)
    старые = []
    for имя in ('прежняя_история', 'прежний_кэш'):
        с = т[имя]
        требовать(type(с) is dict and set(с) == {'путь', 'sha256'} and type(с['sha256']) is str
            and re.fullmatch('[0-9a-f]{64}', с['sha256']) is not None, 'неверный адрес старой пары')
        з = снимок(с['путь']); требовать(з['sha256'] == с['sha256'], 'сырой SHA старой пары не совпадает')
        старые.append(з)
    старое, курсор = (модель._путь(з['путь']) for з in старые)
    требовать(старое.is_relative_to(корень), 'прежняя история вне своего checkout')
    требовать(not курсор.is_relative_to(корень) and not any(os.path.lexists(р/'.git') for р in курсор.parents),
        'старый курсор должен быть вне Git')
    пути = (источник, кэш, история, старое, курсор, модель._путь(str(кэш)+'.lock'), модель._путь(str(курсор)+'.lock'))
    требовать(len(set(пути)) == len(пути), 'совпадающие пути переноса и замков')
    требовать(кэш.parent.is_dir(), 'родитель нового курсора отсутствует')
    if новые_отсутствуют:
        требовать(not os.path.lexists(кэш) and not os.path.lexists(история),
            'новая пара уже существует; используйте адресное восстановление')
    _, _, прежняя, _ = перенос.прочитать_подтверждённую_историю(п['задача'], курсор, старое)
    требовать(not прежняя['пропуски'], 'прежняя модель содержит пропуски')
    автор.составить_имя(п['имя_автора'], прежняя['последнее'])
    return {'схема': 'fum.план-переноса-модели-этапа.1', 'вход_sha256': хэш(байты(п)), 'задача': п['задача'],
        'корень': str(корень), 'источник': str(источник), 'кэш': str(кэш), 'история': str(история),
        'прежняя_пара': старые, 'код': замыкание_кода()}


def предварить(п, т):
    """До start проверяет адреса, полную старую пару, SHA/stat и код; источник может дописываться."""
    return _предварить(п, т, новые_отсутствуют=True)


def сверить(п, т, план, *, восстановление=False):
    требовать(_предварить(п, т, новые_отсутствуют=not восстановление) == план,
        'дрейф пары, адресов или замыкания кода переноса')


def выполнить(п, т, план, *, вызов=None):
    """После stock start/mkdir: dry, пересверка, write. Частичный результат сохраняется."""
    запуск = вызов or (lambda имя, ф: ф())
    сверить(п, т, план)
    корень, источник, кэш, история = назначения(п)
    наблюдённая_метка = чтение._метка(источник.stat())
    аргументы = {'корень_репозитория': корень, 'прежний_кэш': т['прежний_кэш']['путь'],
        'прежняя_история': т['прежняя_история']['путь'], 'кэш': кэш, 'история': история}
    def сухой():
        р = перенос.перенести(источник, п['задача'], **аргументы, без_записи=True)
        проверить_модель(п, р); return р
    проба = запуск('Сухой штатный перенос модели', сухой)
    def граница():
        сверить(п, т, план)
        требовать(чтение._метка(источник.stat()) == наблюдённая_метка, 'дрейф источника между dry и write')
    запуск('Пересверить модель перед записью', граница)
    результат = запуск('Штатный перенос модели', lambda: перенос.перенести(источник, п['задача'], **аргументы))
    def завершение():
        сверить(п, т, план, восстановление=True)
        требовать(чтение._метка(источник.stat()) == наблюдённая_метка, 'дрейф источника при записи; нужен обычный импорт новой пары')
        проверить_модель(п, результат)
        требовать(all(проба[к] == результат[к] for к in ('история_sha256', 'последнее', 'число_наблюдений')),
            'dry и write модели различаются; prepare запрещён')
    запуск('Пересверить завершённый перенос', завершение)
    return {'сухой': проба, 'перенос': результат}


def импортировать_существующую(источник, задача, **аргументы):
    """Штатный importer; запрет полного приёма даже при утрате курсора в check→use.

    Ограниченный thread-local profile hook останавливает вход в _приём(None)
    до чтения/разбора префикса. Исходники и API обычного читателя не меняются;
    Занятый profile hook закрыто отклоняется до установки; состояние свободного
    hook восстанавливается при любом исходе, включая отказ самой установки.
    """
    прежний = sys.getprofile()
    требовать(прежний is None, 'адресное восстановление требует свободный profile hook')
    код_приёма = модель._приём.__code__
    def граница(рамка, событие, аргумент):
        if событие == 'call' and рамка.f_code is код_приёма:
            требовать(рамка.f_locals['прежний'] is not None,
                'новый курсор утрачен внутри импорта; полный fallback запрещён')
    try:
        sys.setprofile(граница)
        return модель.импортировать(источник, задача, **аргументы)
    finally:
        sys.setprofile(прежний)


def _восстановить(п, т, план):
    """Только обычный импорт той же новой пары; отсутствие курсора закрывает fallback."""
    сверить(п, т, план, восстановление=True)
    корень, источник, кэш, история = назначения(п)
    требовать(кэш.exists(), 'новый курсор утрачен; полный fallback и повтор transfer запрещены')
    оболочка = чтение._разобрать(модель._прочитать(кэш, True))
    требовать(type(оболочка) is dict and set(оболочка) == {'данные', 'sha256'}, 'повреждён новый курсор')
    д = оболочка['данные']
    требовать(type(д) is dict and хэш(байты(д)) == оболочка['sha256']
        and д.get('назначение') == str(история) and д.get('реализация') == модель._РЕАЛИЗАЦИЯ
        and д.get('история', {}).get('задача') == п['задача']
        and (д.get('ожидаемый_sha256') is None or (д.get('подготовлено') is True
            and type(д.get('ожидаемый_sha256')) is str
            and re.fullmatch('[0-9a-f]{64}', д['ожидаемый_sha256']) is not None))
        and type(д.get('подготовлено')) is bool, 'чужая или повреждённая новая пара')
    пара = [снимок(кэш), снимок(история) if история.exists() else None]
    метка = чтение._метка(источник.stat())
    аргументы = {'корень_репозитория': корень, 'кэш': кэш, 'история': история}
    проба = импортировать_существующую(источник, п['задача'], **аргументы, без_записи=True)
    проверить_модель(п, проба)
    сверить(п, т, план, восстановление=True)
    требовать(чтение._метка(источник.stat()) == метка
        and [снимок(кэш), снимок(история) if история.exists() else None] == пара,
        'дрейф новой пары или источника перед восстановлением')
    р = импортировать_существующую(источник, п['задача'], **аргументы)
    сверить(п, т, план, восстановление=True); проверить_модель(п, р)
    требовать(чтение._метка(источник.stat()) == метка
        and all(проба[к] == р[к] for к in ('история_sha256', 'последнее', 'число_наблюдений')),
        'дрейф при восстановлении; prepare запрещён')
    return р


def допуск_восстановления(п):
    # Ленивый импорт разрывает цикл с фасадом; исполняемый адресный контур прежний.
    import подготовка_этапа_коммита as этап
    требовать(set(п) == этап.коммит.ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ
        and п['схема'] == 'fum.создание-коммита.5' and п['режим'] == 'контрольная-точка',
        'восстановление принимает точный обычный ROOT .5')
    корень = этап.адреса.проверить_пути(п)
    требовать(п['история_модели'] in п['разрешённые_цели']
        and п['история_модели'] == (Path(п['запрос']).parent/'материалы/история-модели.json').as_posix(),
        'новая модель вне точного разрешения текущего ROOT этапа')
    этап.проверить_корневой_контур(п, корень, True)
    этап.коммит.адрес(п)
    этап.коммит.разрешённые_цели(корень, п)
    return корень


def восстановить(п, т, план):
    """Адресный ROOT допуск до и после восстановления; готовность не объявляется."""
    допуск_восстановления(п)
    р = _восстановить(п, т, план)
    допуск_восстановления(п)
    return р


def главная(аргументы=None):
    р = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    р.add_argument('действие', choices=['восстановить'])
    for имя in ('вход', 'перенос', 'план', 'sha256'):
        р.add_argument('--'+имя, required=True)
    а = р.parse_args(аргументы)
    try:
        д = модель._прочитать(модель._путь(а.план), True)
        требовать(хэш(д) == а.sha256, 'неверный сырой SHA плана переноса')
        итог = восстановить(чтение._разобрать(модель._прочитать(модель._путь(а.вход), True)),
            чтение._разобрать(модель._прочитать(модель._путь(а.перенос), True)), чтение._разобрать(д))
        sys.stdout.buffer.write(байты(итог)); return 0
    except (ValueError, OSError, KeyError, TypeError) as ошибка:
        print(str(ошибка), file=sys.stderr); return 1


if __name__ == '__main__':
    raise SystemExit(главная())

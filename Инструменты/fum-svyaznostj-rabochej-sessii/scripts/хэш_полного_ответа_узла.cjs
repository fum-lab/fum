// SHA-256 и UTF-8 без Node, Buffer или TextEncoder; полный RAW остаётся данными.
function вычислить_отпечаток(текст) {
    if (typeof текст !== "string") throw new Error("Нужна строка");
    let размер = 0;
    for (const знак of текст) {
        let код = знак.codePointAt(0);
        if (код >= 0xd800 && код <= 0xdfff) код = 0xfffd;
        размер += код < 128 ? 1 : код < 2048 ? 2 : код < 65536 ? 3 : 4;
        if (размер > 67108864) throw new Error("Превышен предел полного ответа");
    }
    const данные = new Uint8Array(Math.ceil((размер + 9) / 64) * 64);
    let позиция = 0;
    for (const знак of текст) {
        let код = знак.codePointAt(0);
        if (код >= 0xd800 && код <= 0xdfff) код = 0xfffd;
        if (код < 128) данные[позиция++] = код;
        else if (код < 2048) { данные[позиция++] = 0xc0 | (код >> 6); данные[позиция++] = 0x80 | (код & 63); }
        else if (код < 65536) { данные[позиция++] = 0xe0 | (код >> 12); данные[позиция++] = 0x80 | ((код >> 6) & 63); данные[позиция++] = 0x80 | (код & 63); }
        else { данные[позиция++] = 0xf0 | (код >> 18); данные[позиция++] = 0x80 | ((код >> 12) & 63); данные[позиция++] = 0x80 | ((код >> 6) & 63); данные[позиция++] = 0x80 | (код & 63); }
    }
    данные[размер] = 128;
    let биты = размер * 8;
    for (let сдвиг = 0; сдвиг < 8; сдвиг++) { данные[данные.length - 1 - сдвиг] = биты % 256; биты = Math.floor(биты / 256); }
    const константы = [0x428a2f98,0x71374491,0xb5c0fbcf,0xe9b5dba5,0x3956c25b,0x59f111f1,0x923f82a4,0xab1c5ed5,0xd807aa98,0x12835b01,0x243185be,0x550c7dc3,0x72be5d74,0x80deb1fe,0x9bdc06a7,0xc19bf174,0xe49b69c1,0xefbe4786,0x0fc19dc6,0x240ca1cc,0x2de92c6f,0x4a7484aa,0x5cb0a9dc,0x76f988da,0x983e5152,0xa831c66d,0xb00327c8,0xbf597fc7,0xc6e00bf3,0xd5a79147,0x06ca6351,0x14292967,0x27b70a85,0x2e1b2138,0x4d2c6dfc,0x53380d13,0x650a7354,0x766a0abb,0x81c2c92e,0x92722c85,0xa2bfe8a1,0xa81a664b,0xc24b8b70,0xc76c51a3,0xd192e819,0xd6990624,0xf40e3585,0x106aa070,0x19a4c116,0x1e376c08,0x2748774c,0x34b0bcb5,0x391c0cb3,0x4ed8aa4a,0x5b9cca4f,0x682e6ff3,0x748f82ee,0x78a5636f,0x84c87814,0x8cc70208,0x90befffa,0xa4506ceb,0xbef9a3f7,0xc67178f2];
    const итог = [0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a,0x510e527f,0x9b05688c,0x1f83d9ab,0x5be0cd19];
    const слова = new Int32Array(64);
    const повернуть = (число, сдвиг) => (число >>> сдвиг) | (число << (32 - сдвиг));
    for (let блок = 0; блок < данные.length; блок += 64) {
        for (let номер = 0; номер < 16; номер++) { const смещение = блок + номер * 4; слова[номер] = (данные[смещение] << 24) | (данные[смещение+1] << 16) | (данные[смещение+2] << 8) | данные[смещение+3]; }
        for (let номер = 16; номер < 64; номер++) {
            const первое = слова[номер-15], второе = слова[номер-2];
            слова[номер] = (слова[номер-16] + (повернуть(первое,7)^повернуть(первое,18)^(первое>>>3)) + слова[номер-7] + (повернуть(второе,17)^повернуть(второе,19)^(второе>>>10))) | 0;
        }
        let [а,б,в,г,д,е,ж,з] = итог;
        for (let номер = 0; номер < 64; номер++) {
            const первое = (з + (повернуть(д,6)^повернуть(д,11)^повернуть(д,25)) + ((д&е)^(~д&ж)) + константы[номер] + слова[номер]) | 0;
            const второе = ((повернуть(а,2)^повернуть(а,13)^повернуть(а,22)) + ((а&б)^(а&в)^(б&в))) | 0;
            з=ж;ж=е;е=д;д=(г+первое)|0;г=в;в=б;б=а;а=(первое+второе)|0;
        }
        const состояние = [а,б,в,г,д,е,ж,з];
        for (let номер = 0; номер < 8; номер++) итог[номер] = (итог[номер] + состояние[номер]) | 0;
    }
    return {байты: размер, sha256: итог.map(число => (число >>> 0).toString(16).padStart(8,"0")).join("")};
}
if (typeof module !== "undefined") module.exports = {отпечаток_строки:вычислить_отпечаток};

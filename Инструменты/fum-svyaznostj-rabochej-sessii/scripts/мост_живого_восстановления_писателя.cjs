"use strict";

// Один контроллер, четыре фиксированные фазы. JSON не выбирает инструмент.
async function выполнить_живое_восстановление(среда, параметры) {
    const фазы=["read1","read2","send","readback"];
    const шаблон_идентификатора=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
    const шаблон_хэша=/^[0-9a-f]{64}$/;
    const путь=значение=>typeof значение==="string"&&значение.startsWith("/")&&!/[\x00-\x1f]/.test(значение)&&!значение.split("/").some(компонент_пути=>компонент_пути==="."||компонент_пути==="..");
    const поля=(значение,имена_полей)=>значение&&typeof значение==="object"&&!Array.isArray(значение)&&Object.keys(значение).sort().join(",")===имена_полей.slice().sort().join(",");
    const кавычки=значение=>"'"+значение.split("'").join("'\\''")+"'";
    const размер=текст=>{let число=0;for(const символ of текст){const элемент=символ.codePointAt(0);число+=элемент<128?1:элемент<2048?2:элемент<65536?3:4;}return число;};
    let сеанс=null,номер=0,чтений=0,отправок=0,цикл=null,задача=null,хост=null,буфер="",подтверждение=null,ожидает=null;
    const отказ=причина=>({схема:"fum.мост-живого-восстановления.1",состояние:"не принят",
        фаза:фазы[номер]||"конец",чтений_инструментов:чтений,отправок_инструментов:отправок,причина,
        исход_эффекта:"unknown",приёмка:"unknown"});
    try {
        const имена=["корень","вход","вход_sha256","выбор","выбор_sha256","контейнер","писатель","писатель_sha256","читатель","читатель_sha256"];
        if(!параметры||Object.keys(параметры).some(элемент=>!имена.concat("лимит_аргумента").includes(элемент))||
            имена.some(элемент=>элемент.endsWith("sha256")?!шаблон_хэша.test(параметры[элемент]):!путь(параметры[элемент])))throw Error("Недопустимый вход моста");
        const лимит=параметры.лимит_аргумента??262144;
        if(!Number.isInteger(лимит)||лимит<512||лимит>262144)throw Error("Недопустимый предел");
        const набор_инструментов=среда.инструменты;
        if(![среда.хэш,набор_инструментов?.exec_command,набор_инструментов?.write_stdin,набор_инструментов?.mcp__codex_app__read_thread,
            набор_инструментов?.mcp__codex_app__send_message_to_thread].every(значение=>typeof значение==="function"))throw Error("Нет фиксированных инструментов");
        // Интерпретатор закрепляет доверенная среда, а не сериализованный input/RAW.
        if(!путь(среда.интерпретатор)||среда.интерпретатор.split("/").at(-1)!=="python3.14")throw Error("Нужен выбранный абсолютный Python 3.14");
        const аргументы=[среда.интерпретатор,"-B",
            параметры.корень+"/Инструменты/fum-svyaznostj-rabochej-sessii/scripts/живое_восстановление_писателя.py"];
        for(const элемент of имена)аргументы.push("--"+элемент.replaceAll("_","-"),параметры[элемент]);
        let результат_процесса=await набор_инструментов.exec_command({cmd:аргументы.map(кавычки).join(" "),workdir:параметры.корень,
            tty:true,yield_time_ms:1000,max_output_tokens:60000});
        if(Number.isInteger(результат_процесса.session_id))сеанс=результат_процесса.session_id;
        let опросов=0;
        while(true) {
            буфер+=(результат_процесса.output||"").replaceAll("\r\n","\n");
            if(размер(буфер)>262144)throw Error("Неполный или чрезмерный вывод контроллера");
            let запрос=null;
            while(буфер.includes("\n")) {
                const конец=буфер.indexOf("\n"),строка=буфер.slice(0,конец);буфер=буфер.slice(конец+1);
                if(!строка)continue;
                const сообщение=JSON.parse(строка);
                if(сообщение.схема==="fum.ACK-ответа-живого-восстановления.1") {
                    if(!ожидает||!поля(сообщение,["схема","цикл","фаза","задача","байты","sha256","объект"])||
                        Object.keys(ожидает).some(элемент=>сообщение[элемент]!==ожидает[элемент])||!поля(сообщение.объект,["идентификатор","описание","размер","sha256"])||
                        сообщение.объект.размер!==сообщение.байты||сообщение.объект.sha256!==сообщение.sha256||
                        сообщение.объект.описание?.идентификатор!==сообщение.объект.идентификатор)throw Error("Чужой durable ACK");
                    подтверждение=сообщение;ожидает=null;continue;
                }
                if(сообщение.схема==="fum.живое-восстановление-писателя.1") {
                    if(ожидает||запрос)throw Error("Итог до durable ACK");
                    // Дождаться выхода: прежний итог не запускает новый контроллер.
                    for(let число=0;результат_процесса.exit_code===undefined&&число<30;число++) {
                        результат_процесса=await набор_инструментов.write_stdin({session_id:сеанс,chars:"",yield_time_ms:1000,max_output_tokens:1000});
                        if((результат_процесса.output||"").trim())throw Error("Лишний вывод после итога");
                    }
                    if(результат_процесса.exit_code!==0)throw Error("Выход контроллера неизвестен");
                    return {схема:"fum.мост-живого-восстановления.1",состояние:"контроллер завершён",
                        чтений_инструментов:чтений,отправок_инструментов:отправок,итог:сообщение,приёмка:"unknown"};
                }
                if(запрос||ожидает||!поля(сообщение,["схема","цикл","фаза","задача","параметры"])||
                    сообщение.схема!=="fum.запрос-живого-восстановления.1"||номер>=4||сообщение.фаза!==фазы[номер]||
                    !шаблон_идентификатора.test(сообщение.цикл)||!шаблон_идентификатора.test(сообщение.задача))throw Error("Повтор, перестановка или неизвестный запрос");
                if(цикл===null){цикл=сообщение.цикл;задача=сообщение.задача;хост=сообщение.параметры?.hostId;}
                if(сообщение.цикл!==цикл||сообщение.задача!==задача||сообщение.параметры?.threadId!==задача||
                    typeof хост!=="string"||!хост||сообщение.параметры.hostId!==хост)throw Error("Дрейф адресата");
                const параметры_вызова=сообщение.параметры;
                if(сообщение.фаза==="send") {
                    if(!поля(параметры_вызова,["threadId","hostId","prompt","model","thinking"])||typeof параметры_вызова.prompt!=="string"||
                        !параметры_вызова.prompt.trim()||размер(параметры_вызова.prompt)>65536||параметры_вызова.prompt.includes("\0")||typeof параметры_вызова.model!=="string"||!параметры_вызова.model||
                        !["none","minimal","low","medium","high","xhigh","max","ultra"].includes(параметры_вызова.thinking))throw Error("Недопустимый send");
                } else if(!поля(параметры_вызова,["threadId","hostId","turnLimit","includeOutputs","maxOutputCharsPerItem"])||
                    параметры_вызова.turnLimit!==1||параметры_вызова.includeOutputs!==true||параметры_вызова.maxOutputCharsPerItem!==16000)throw Error("Недопустимое latest-чтение");
                запрос=сообщение;
            }
            if(!запрос) {
                if(результат_процесса.exit_code!==undefined||!Number.isInteger(сеанс)||++опросов>600)throw Error("Контроллер не выдал конечный запрос");
                результат_процесса=await набор_инструментов.write_stdin({session_id:сеанс,chars:"",yield_time_ms:1000,max_output_tokens:60000});continue;
            }
            опросов=0;
            if(буфер.trim())throw Error("Незавершённый хвост после запроса");
            if(!Number.isInteger(сеанс)||результат_процесса.exit_code!==undefined)throw Error("Контроллер уже завершён; запрос не разрешает API");
            let ответ;
            if(запрос.фаза==="send") {отправок++;ответ=await набор_инструментов.mcp__codex_app__send_message_to_thread(запрос.параметры);}
            else {чтений++;ответ=await набор_инструментов.mcp__codex_app__read_thread(запрос.параметры);}
            if(!ответ||typeof ответ!=="object")throw Error("Нет полного доступного ответа API");
            const сериализованный_ответ=JSON.stringify(ответ),отпечаток=среда.хэш(сериализованный_ответ);
            if(!поля(отпечаток,["байты","sha256"])||!Number.isInteger(отпечаток.байты)||отпечаток.байты!==размер(сериализованный_ответ)||
                отпечаток.байты<1||отпечаток.байты>67108864||!шаблон_хэша.test(отпечаток.sha256))throw Error("Недопустимые байты ответа");
            ожидает={цикл,фаза:запрос.фаза,задача,...отпечаток};
            const заголовок={схема:"fum.передача-ответа-живого-восстановления.1",...ожидает};
            const завершение={...заголовок,схема:"fum.конец-ответа-живого-восстановления.1"};
            const кадр=JSON.stringify(заголовок)+"\n"+сериализованный_ответ+"\n"+JSON.stringify(завершение)+"\n";
            let позиция=0,вывод="";
            while(позиция<кадр.length) {
                let нижняя_граница=1,верхняя_граница=Math.min(100000,кадр.length-позиция),число=0;
                while(нижняя_граница<=верхняя_граница){const середина=Math.floor((нижняя_граница+верхняя_граница)/2),параметры_вызова={session_id:сеанс,chars:кадр.slice(позиция,позиция+середина),yield_time_ms:1000,max_output_tokens:60000};
                    if(размер(JSON.stringify(параметры_вызова))<=лимит){число=середина;нижняя_граница=середина+1;}else верхняя_граница=середина-1;}
                const последний_код=кадр.charCodeAt(позиция+число-1),следующий_код=кадр.charCodeAt(позиция+число);
                if(последний_код>=0xd800&&последний_код<=0xdbff&&следующий_код>=0xdc00&&следующий_код<=0xdfff)число--;
                if(число<1)throw Error("Порция не помещается");
                результат_процесса=await набор_инструментов.write_stdin({session_id:сеанс,chars:кадр.slice(позиция,позиция+число),yield_time_ms:1000,max_output_tokens:60000});
                позиция+=число;вывод+=результат_процесса.output||"";
                if(размер(вывод)>262144||результат_процесса.exit_code!==undefined&&(результат_процесса.exit_code!==0||позиция!==кадр.length)||
                    результат_процесса.exit_code===undefined&&результат_процесса.session_id!==сеанс)throw Error("Исход приёмника неизвестен");
            }
            результат_процесса={...результат_процесса,output:вывод};номер++;
        }
    } catch(ошибка) {
        if(сеанс!==null)try{await среда.инструменты.write_stdin({session_id:сеанс,chars:"\u0003",yield_time_ms:1000,max_output_tokens:1000});}catch(_){}
        return отказ(String(ошибка?.message||"Неизвестный исход"));
    }
}

if(typeof module!=="undefined")module.exports={выполнить_живое_восстановление};

def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True,
        separators=(',', ':'), allow_nan=False) + '\n').encode()


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def разобрать(данные):
    def пары(значения):
        итог = {}
        for ключ, значение in значения:
            требовать(ключ not in итог, 'Повторный ключ JSON')
            итог[ключ] = значение
        return итог
    return json.loads(данные.decode('utf-8'), object_pairs_hook=пары,
        parse_constant=lambda _: требовать(False, 'Необычное число JSON'))


def поля(значение, имена):
    требовать(type(значение) is dict and set(значение) == set(имена), 'Неверные закрытые поля')


def путь(значение):
    требовать(type(значение) is str, 'Нужен строковый физический путь')
    итог = Path(значение)
    требовать(итог.is_absolute() and str(итог) == значение and итог.resolve() == итог
        and not any(п.is_symlink() for п in (итог, *итог.parents)), 'Перенаправленный путь')
    return итог


def прочитать(значение, *, двоичный=False):
    файл = путь(str(значение))
    до = файл.lstat()
    требовать(stat.S_ISREG(до.st_mode) and (двоичный or до.st_nlink == 1) and до.st_size <= 64 * 1024 * 1024,
        'Нужен ограниченный обычный файл без жёсткой ссылки')
    with os.fdopen(os.open(файл, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK), 'rb') as поток:
        требовать(осмотр(до) == осмотр(os.fstat(поток.fileno())), 'Подмена открываемого файла')
        данные = поток.read(64 * 1024 * 1024 + 1)
        ЧТЕНИЯ['файлов'] += 1
        ЧТЕНИЯ['байтов_файлов'] += len(данные)
        требовать(осмотр(до) == осмотр(os.fstat(поток.fileno())) == осмотр(файл.lstat()),
            'Файл изменился при чтении')
    return данные


def осмотр(сведения):
    return (сведения.st_dev, сведения.st_ino, сведения.st_mode, сведения.st_nlink,
        сведения.st_size, сведения.st_mtime_ns, сведения.st_ctime_ns)


@contextmanager
def фаза(имя):
    начало, цпу, дочерние, процессы = time.perf_counter_ns(), time.process_time_ns(), resource.getrusage(resource.RUSAGE_CHILDREN), ПРОЦЕССЫ
    успех = False
    чтения = dict(ЧТЕНИЯ)
    счётчики = {'деревьев': 0, 'блобов': 0, 'байтов_предмета': 0}
    try:
        yield счётчики
        успех = True
    finally:
        после = resource.getrusage(resource.RUSAGE_CHILDREN)
        ПРОФИЛЬ.setdefault(имя, []).append({'длительность_наносекунды': time.perf_counter_ns() - начало,
            'ЦПУ_процесса_наносекунды': time.process_time_ns() - цпу,
            'ЦПУ_дочерних_наносекунды': round(1e9 * (после.ru_utime + после.ru_stime - дочерние.ru_utime - дочерние.ru_stime)),
            'процессов': ПРОЦЕССЫ - процессы, 'успех': успех,
            'чтения': {имя: значение - чтения[имя] for имя, значение in ЧТЕНИЯ.items()}, **счётчики})


def загрузить_код(описание):
    """Внешний ROOT-вход закрепляет полный экспорт Python цельной C572 до import."""
    поля(описание, {'коммит', 'корень', 'файлы'})
    требовать(описание['коммит'] == ОСНОВА_КОДА, 'Нужна цельная C572')
    корень = путь(описание['корень'])
    требовать(type(описание['файлы']) is dict and описание['файлы'], 'Нет закреплённого контура C572')
    требовать(хэш(байты(описание['файлы'])) == КОНТУР_КОДА, 'Манифест не является цельной C572')
    for каталог, папки, файлы in os.walk(корень / 'Инструменты', followlinks=False):
        требовать('__pycache__' not in папки and not any(имя.endswith(('.pyc', '.pyo', '.so', '.dylib', '.pyd')) for имя in файлы),
            'Кэш или двоичная альтернатива Python запрещены')
        требовать(not any((Path(каталог) / имя).is_symlink() for имя in папки), 'Ссылка в контуре кода')
    буферы = {str(ф): прочитать(ф) for ф in (корень / 'Инструменты').rglob('*.py')}
    найденные = {str(Path(имя).relative_to(корень)): хэш(данные) for имя, данные in буферы.items()}
    требовать(найденные == описание['файлы'], 'Контур C572 неполон или подменён')
    скрипты = корень / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts'
    имена_контура = {Path(имя).name for имя in найденные}
    for модуль in tuple(sys.modules.values()):
        файл = getattr(модуль, '__file__', None)
        if файл and '/Инструменты/' in str(файл) and Path(файл).name in имена_контура:
            физический = Path(файл).resolve()
            if физический == Path(__file__).resolve():
                continue
            требовать(физический.is_relative_to(корень), 'Смешение ранее загруженных проектных модулей')
    sys.path.insert(0, str(скрипты))
    закрепить_загрузку(корень, буферы)
    создатель = importlib.import_module('создание_коммита')
    допуск = importlib.import_module('допуск_создания_базиса_узла')
    построитель = importlib.import_module('построить_дерево_базиса_узла')
    return создатель, допуск, построитель


def закрепить_загрузку(корень, буферы):
    """Source-only import и явные SourceFileLoader используют удержанные байты.

    Ограничение живёт в свежем процессе потребителя; оно не меняет файлы,
    настройки Python или системные пакеты. Повтор использует тот же контур.
    """
    class ИскательИсходников(importlib.abc.MetaPathFinder):
        def __init__(сам):
            сам.закреплённые_буферы = {}
            сам.корни_контуров = set()

        def find_spec(сам, fullname, path=None, target=None):
            имя = fullname.rsplit('.', 1)[-1]
            for каталог in (sys.path if path is None else path):
                база = Path(каталог).absolute()
                if not any(база.is_relative_to(п) for п in сам.корни_контуров): continue
                файл = база / (имя + '.py')
                пакет = база / имя / '__init__.py'
                if str(файл) in сам.закреплённые_буферы:
                    return importlib.util.spec_from_file_location(fullname, файл)
                if str(пакет) in сам.закреплённые_буферы:
                    return importlib.util.spec_from_file_location(fullname, пакет, submodule_search_locations=[str(пакет.parent)])
                требовать(not any(база.glob(имя + '.*')) and not (база / имя).exists(), 'Незакреплённая альтернатива модуля')
            return None
    искатель = next((п for п in sys.meta_path if type(getattr(п, 'закреплённые_буферы', None)) is dict), None)
    if искатель is None:
        искатель = ИскательИсходников()
        загрузчик = importlib.machinery.SourceFileLoader
        прежний = загрузчик.get_code
        def получить(сам, имя):
            файл = str(Path(сам.path).absolute())
            if файл in искатель.закреплённые_буферы:
                return compile(искатель.закреплённые_буферы[файл], файл, 'exec', dont_inherit=True)
            return прежний(сам, имя)
        загрузчик.get_code = получить
        sys.meta_path.insert(0, искатель)
    for имя, данные in буферы.items():
        требовать(имя not in искатель.закреплённые_буферы or искатель.закреплённые_буферы[имя] == данные,
            'Загруженный контур изменился')
        искатель.закреплённые_буферы[имя] = данные
    искатель.корни_контуров.add(корень)


def фиксированный_канал():
    """Один доверенный исполнитель для ROOT-чтения и stdin-конфигурации.

    Ограду вызывает потребитель до repo-aware режима. Сам канал её не вызывает:
    проверка конфигурации использует его из отдельного приватного non-Git cwd.
    """
    def читать(*аргументы, корень=None, ввод=None, рабочий_каталог=None, причина='Фиксированный Git отказал'):
        требовать((корень is None) != (рабочий_каталог is None), 'Нужен один явный режим fixed Git')
        среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
        среда.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_SYSTEM=os.devnull, GIT_CONFIG_GLOBAL=os.devnull,
            GIT_NO_LAZY_FETCH='1', GIT_NO_REPLACE_OBJECTS='1', GIT_TERMINAL_PROMPT='0', GIT_PAGER='cat')
        команды = ['-C', str(корень), *аргументы] if корень is not None else list(аргументы)
        процесс = subprocess.run(['/usr/bin/git', '--no-optional-locks', '--no-replace-objects',
            '-c', 'core.hooksPath=' + os.devnull, '-c', 'core.fsmonitor=false', '-c', 'gc.auto=0',
            '-c', 'maintenance.auto=false', '-c', 'trace2.normalTarget=0', '-c', 'trace2.eventTarget=0',
            '-c', 'trace2.perfTarget=0', '-c', 'protocol.allow=never', *команды],
            input=ввод, cwd=рабочий_каталог, capture_output=True, env=среда, timeout=30)
        ЧТЕНИЯ['ответов_Гит'] += 1
        ЧТЕНИЯ['байтов_Гит'] += len(процесс.stdout)
        требовать(процесс.returncode == 0, причина)
        return процесс.stdout
    return читать


def прочитать_назначение(отчёт, селектор, *, ограда=None):
    """Минимальный bootstrap до любого import из выбранного экспорта.

    Селектор передаётся независимо вызывающим ROOT. Системный Git здесь
    фиксирован, candidate и его PATH/config не выбирают исполняемый файл.
    """
    поля(селектор, {'коммит', 'путь', 'sha256'})
    требовать(re.fullmatch('[0-9a-f]{40}', селектор['коммит'])
        and re.fullmatch('[0-9a-f]{64}', селектор['sha256']), 'Неверный selector ROOT')
    имя = селектор['путь']
    требовать(type(имя) is str and not Path(имя).is_absolute() and '\\' not in имя
        and all(ч not in ('', '.', '..', '.git') for ч in имя.split('/'))
        and all(ord(ч) >= 32 and ord(ч) != 127 for ч in имя), 'Неверное имя ROOT blob')
    фиксированный = фиксированный_канал()
    def читать(*аргументы):
        if ограда is not None: ограда(путь(отчёт))
        return фиксированный(*аргументы, корень=путь(отчёт), причина='Bootstrap ROOT отказал')
    требовать(читать('cat-file', '-t', селектор['коммит']).strip() == b'commit', 'ROOT selector не коммит')
    записи = [э for э in читать('ls-tree', '-rz', селектор['коммит']).split(b'\0')
        if э and э.split(b'\t', 1)[1] == имя.encode()]
    требовать(len(записи) == 1 and записи[0].startswith(b'100644 blob '), 'ROOT требует единственный обычный blob')
    объект = записи[0].split(b'\t', 1)[0].split(b' ')[2].decode()
    данные = читать('cat-file', 'blob', объект)
    требовать(хэш(данные) == селектор['sha256'], 'Подменён независимый ROOT blob')
    return разобрать(данные)


def канал_гита(выбор, создатель, допуск, *, ограда=None):
    штатный = допуск.выбрать_гит(выбор, создатель)
    def параметры(корень, аргументы):
        среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
        среда.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_SYSTEM=os.devnull,
            GIT_CONFIG_GLOBAL=os.devnull, GIT_ATTR_NOSYSTEM='1', GIT_NO_REPLACE_OBJECTS='1',
            GIT_NO_LAZY_FETCH='1', GIT_TERMINAL_PROMPT='0')
        команда = [выбор['гит']['путь'], '--no-optional-locks', '--no-replace-objects',
            '-c', 'core.hooksPath=' + os.devnull, '-c', 'core.fsmonitor=false', '-c', 'core.fileMode=true',
            '-c', 'core.attributesFile=' + os.devnull, '-c', 'submodule.recurse=false',
            '-c', 'gc.auto=0', '-c', 'maintenance.auto=false', '-c', 'protocol.allow=never',
            '-C', str(корень), *аргументы]
        return команда, среда
    def читать(корень, *аргументы, ввод=None):
        if ограда is not None: ограда(корень)
        команда, среда = параметры(корень, аргументы)
        процесс = subprocess.run(команда, input=ввод, capture_output=True, env=среда, timeout=30)
        ЧТЕНИЯ['ответов_Гит'] += 1
        ЧТЕНИЯ['байтов_Гит'] += len(процесс.stdout)
        требовать(процесс.returncode == 0, 'Git-канал подготовки отказал')
        return процесс.stdout
    def деревья(корень, ожидаемые, хранилище):
        команда, среда = параметры(корень, ('cat-file', '--batch-command'))
        return пакетный_канал_деревьев(команда, среда, корень, ожидаемые, ограда, хранилище)
    читать.деревья = деревья
    return читать


def пакетный_канал_деревьев(команда, среда, корень, ожидаемые, ограда, хранилище):
    """Один конечный поток, без сохранения процесса или ответов между вызовами.

    Deadline отдельный для отправки, заголовка, тела и завершения; частичные
    операции его не продлевают. Заголовок не забирает сырое тело до ограды.
    """
    ПАКЕТНЫЕ_ДЕРЕВЬЯ['вызовов'] += 1
    процесс = None
    успех = False
    try:
        требовать(type(ожидаемые) is dict, 'Нужен конечный набор деревьев')
        записи = sorted(ожидаемые.items())
        for объект, данные in записи:
            требовать(type(объект) is str and re.fullmatch('[0-9a-f]{40}', объект)
                and type(данные) is bytes, 'Неверное выбранное дерево')
            требовать(hashlib.sha1(b'tree ' + str(len(данные)).encode() + b'\0' + данные).hexdigest() == объект,
                'Выбранные сырые байты не связаны с OID дерева')
        if not записи:
            успех = True
            return []
        хранилище = путь(str(хранилище))
        def состояние_хранилища():
            # Удержанный Git может хранить pack mmap/delta cache. Ни выбранный
            # loose-объект, ни физический pack-контур не меняются в его lifetime.
            ПАКЕТНЫЕ_ДЕРЕВЬЯ['осмотров_хранилища'] += 1
            итог = {}
            def осмотреть(п, *, каталог=False, необязательный=False, идентичность=False):
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['осмотров_путей'] += 1
                try: с = п.lstat()
                except FileNotFoundError:
                    требовать(необязательный, 'Исчезла физическая база объектов')
                    итог[str(п)] = None
                    требовать(len(итог) <= 65536, 'Слишком большой физический контур pack')
                    return False
                требовать(stat.S_ISDIR(с.st_mode) if каталог else stat.S_ISREG(с.st_mode),
                    'Перенаправленный путь физической базы объектов')
                итог[str(п)] = (с.st_dev, с.st_ino, с.st_mode) if идентичность else осмотр(с)
                требовать(len(итог) <= 65536, 'Слишком большой физический контур pack')
                return True
            осмотреть(хранилище, каталог=True, идентичность=True)
            пакет = хранилище / 'pack'
            def отказ_обхода(ошибка):
                raise ошибка
            if осмотреть(пакет, каталог=True, необязательный=True):
                for каталог, папки, файлы in os.walk(пакет, followlinks=False, onerror=отказ_обхода):
                    for имя in sorted(папки): осмотреть(Path(каталог) / имя, каталог=True)
                    for имя in sorted(файлы): осмотреть(Path(каталог) / имя)
            for префикс in sorted({о[:2] for о, _ in записи}):
                if осмотреть(хранилище / префикс, каталог=True, необязательный=True, идентичность=True):
                    for объект, _ in записи:
                        if объект.startswith(префикс):
                            осмотреть(хранилище / префикс / объект[2:], необязательный=True)
            return итог
        исходное_хранилище = состояние_хранилища()
        def сверить_хранилище():
            требовать(состояние_хранилища() == исходное_хранилище, 'Дрейф физической базы объектов пакетного канала')
        итог = []
        открытые = set()
        def срок():
            return time.monotonic() + ТАЙМ_АУТ_ПАКЕТА
        def ждать(до, *, запись=False):
            while True:
                остаток = до - time.monotonic()
                требовать(остаток > 0, 'Тайм-аут пакетного канала деревьев')
                try:
                    чтение, запись_готова, _ = select.select(list(открытые),
                        [процесс.stdin.fileno()] if запись else [], [], остаток)
                    return чтение, запись_готова
                except InterruptedError:
                    continue
        def ошибки(готовые):
            дескриптор = процесс.stderr.fileno()
            if дескриптор in готовые:
                try: данные = os.read(дескриптор, 65536)
                except (BlockingIOError, InterruptedError): return
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_ошибок'] += len(данные)
                требовать(ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_ошибок'] - ошибки_до <= 65536,
                    'Слишком большой stderr пакетного канала')
                if not данные: открытые.discard(дескриптор)
        def получить(размер, до):
            while процесс.stdout.fileno() in открытые:
                готовые, _ = ждать(до)
                ошибки(готовые)
                if процесс.stdout.fileno() in готовые:
                    try: данные = os.read(процесс.stdout.fileno(), размер)
                    except (BlockingIOError, InterruptedError): continue
                    ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_вывода'] += len(данные)
                    if not данные: открытые.discard(процесс.stdout.fileno())
                    return данные
            return b''
        def отправить(запрос):
            смещение, до = 0, срок()
            while смещение < len(запрос):
                готовые, готов_ввод = ждать(до, запись=True)
                ошибки(готовые)
                if процесс.stdout.fileno() in готовые:
                    # До отправки очередного запроса не разрешены даже пустой
                    # преждевременный EOF или один лишний байт.
                    получить(1, до)
                    требовать(False, 'Непрошенный ответ пакетного канала')
                if готов_ввод:
                    try: число = os.write(процесс.stdin.fileno(), запрос[смещение:])
                    except (BlockingIOError, InterruptedError): continue
                    требовать(число > 0, 'Закрытый ввод пакетного канала')
                    смещение += число
                    ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_ввода'] += число
            ПАКЕТНЫЕ_ДЕРЕВЬЯ['запросов'] += 1
        def прочитать_заголовок(допустимые):
            заголовок, до = bytearray(), срок()
            while not заголовок.endswith(b'\n'):
                требовать(len(заголовок) < max(map(len, допустимые)), 'Длинный заголовок tree')
                часть = получить(1, до)
                требовать(часть, 'Оборванный заголовок tree')
                заголовок.extend(часть)
            требовать(заголовок in допустимые, 'Неверный OID/type/size/header дерева')
            ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_заголовков'] += len(заголовок)
            return bytes(заголовок)
        ошибки_до = ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_ошибок']
        for объект, данные in записи:
            if ограда is not None: ограда(корень)
            сверить_хранилище()
            if процесс is None:
                процесс = subprocess.Popen(команда, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE, env=среда, bufsize=0)
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['процессов'] += 1
                for поток in (процесс.stdin, процесс.stdout, процесс.stderr):
                    os.set_blocking(поток.fileno(), False)
                открытые.update((процесс.stdout.fileno(), процесс.stderr.fileno()))
            отсутствует = (объект + ' missing\n').encode()
            присутствует = (объект + ' tree ' + str(len(данные)) + '\n').encode()
            отправить(('info ' + объект + '\n').encode())
            заголовок = прочитать_заголовок((отсутствует, присутствует))
            if заголовок == отсутствует:
                итог.append(объект)
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['отсутствующих'] += 1
            else:
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['ответов'] += 1
                if ограда is not None: ограда(корень)
                сверить_хранилище()
                отправить(('contents ' + объект + '\n').encode())
                прочитать_заголовок((присутствует,))
                до, смещение = срок(), 0
                проверка = hashlib.sha1(b'tree ' + str(len(данные)).encode() + b'\0')
                while смещение < len(данные):
                    часть = получить(min(65536, len(данные) - смещение), до)
                    требовать(часть and часть == данные[смещение:смещение + len(часть)], 'Подменённое raw дерева')
                    проверка.update(часть); смещение += len(часть)
                требовать(получить(1, до) == b'\n' and проверка.hexdigest() == объект,
                    'Неверный разделитель или raw OID дерева')
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_содержимого'] += len(данные)
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_разделителей'] += 1
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['объектов'] += 1
            ПАКЕТНЫЕ_ДЕРЕВЬЯ['ответов'] += 1
            сверить_хранилище()
        процесс.stdin.close()
        до = срок()
        требовать(получить(1, до) == b'', 'Лишние данные после tree-ответов')
        while открытые:
            готовые, _ = ждать(до)
            ошибки(готовые)
        требовать(до > time.monotonic(), 'Тайм-аут пакетного канала деревьев')
        требовать(процесс.wait(timeout=до - time.monotonic()) == 0,
            'Пакетный Git отказал')
        сверить_хранилище()
        успех = True
        return итог
    finally:
        исходная_ошибка = sys.exception()
        if not успех: ПАКЕТНЫЕ_ДЕРЕВЬЯ['отказов'] += 1
        if процесс is not None:
            сбои = []
            try:
                if процесс.poll() is None:
                    try: процесс.terminate()
                    except ProcessLookupError: pass
                    except OSError as ошибка: сбои.append(str(ошибка))
                    try: процесс.wait(timeout=1)
                    except (OSError, subprocess.SubprocessError) as ошибка_ожидания:
                        if not isinstance(ошибка_ожидания, subprocess.TimeoutExpired):
                            сбои.append(str(ошибка_ожидания))
                        try: процесс.kill()
                        except ProcessLookupError: pass
                        except OSError as ошибка: сбои.append(str(ошибка))
                        try: процесс.wait(timeout=1)
                        except (OSError, subprocess.SubprocessError) as ошибка: сбои.append(str(ошибка))
            except (OSError, subprocess.SubprocessError) as ошибка:
                сбои.append(str(ошибка))
            finally:
                for поток in (процесс.stdin, процесс.stdout, процесс.stderr):
                    try: поток.close()
                    except OSError as ошибка: сбои.append(str(ошибка))
            if сбои:
                ПАКЕТНЫЕ_ДЕРЕВЬЯ['сбоев_завершения'] += 1
                if успех: ПАКЕТНЫЕ_ДЕРЕВЬЯ['отказов'] += 1
                raise ValueError((str(исходная_ошибка) + '; ' if исходная_ошибка else '')
                    + 'Ошибки завершения пакетного ребёнка: ' + '; '.join(сбои)) from исходная_ошибка



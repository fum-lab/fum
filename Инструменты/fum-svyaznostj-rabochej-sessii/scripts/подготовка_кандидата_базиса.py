def каталог_гита(значение):
    каталог = путь(str(значение))
    требовать(каталог.is_dir(), 'Неполная Git-область')
    сведения = каталог.stat()
    требовать(stat.S_ISDIR(сведения.st_mode) and сведения.st_uid == os.getuid()
        and not сведения.st_mode & 0o022, 'Чужая или общедоступная Git-область')
    return каталог


def служебные_байты(файл):
    до = файл.lstat()
    требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1 and до.st_uid == os.getuid()
        and not до.st_mode & 0o022 and до.st_size <= 1024 * 1024,
        'Небезопасный источник Git-конфигурации/указателя')
    данные = прочитать(файл)
    сведения = файл.stat()
    требовать(осмотр(до) == осмотр(сведения) and сведения.st_uid == до.st_uid,
        'Источник конфигурации/указателя изменился при чтении')
    return данные


def адрес_указателя(база, данные):
    требовать(данные.endswith(b'\n') and данные.count(b'\n') == 1
        and b'\r' not in данные and b'\0' not in данные, 'Неоднозначный Git-указатель')
    текст = данные[:-1].decode('utf-8')
    требовать(bool(текст), 'Пустой Git-указатель')
    исходный = Path(текст) if Path(текст).is_absolute() else база / текст
    текущий = Path(исходный.anchor)
    for часть in исходный.parts[1:]:
        if часть == '..': текущий = текущий.parent
        elif часть != '.':
            текущий /= часть
            требовать(not текущий.is_symlink(), 'Перенаправленный Git-указатель')
    return путь(str(текущий))


def физические_адреса(корень):
    корень = каталог_гита(корень)
    указатели = {}
    точка = корень / '.git'
    требовать(not точка.is_symlink(), 'Перенаправленная точка Git')
    if точка.is_dir():
        админ = каталог_гита(точка)
    else:
        данные = служебные_байты(точка)
        требовать(данные.startswith(b'gitdir: '), 'Неоднозначный gitfile')
        указатели[точка] = данные
        админ = каталог_гита(адрес_указателя(корень, данные[len(b'gitdir: '):]))
    общий = админ
    указатель = админ / 'commondir'
    if os.path.lexists(указатель):
        данные = служебные_байты(указатель); указатели[указатель] = данные
        общий = каталог_гита(адрес_указателя(админ, данные))
        обратный = админ / 'gitdir'
        данные = служебные_байты(обратный); указатели[обратный] = данные
        требовать(адрес_указателя(админ, данные) == точка, 'Чужая обратная связь worktree')
    каталог_гита(общий / 'objects')
    return админ, общий, указатели


def ограда_конфигурации(песочница, исполнитель=None):
    """Разбор удержанных байтов без обнаружения репозитория и include-целей.

    Кэш ограничен данным контекстом и ключом сырых байтов. Физические источники
    читаются заново перед каждым вызовом; кэш не заменяет проверку свежести.
    """
    песочница = путь(str(песочница))
    def проверить_контекст():
        путь(str(песочница))
        сведения = песочница.stat()
        требовать(песочница.is_dir() and сведения.st_uid == os.getuid()
            and not сведения.st_mode & 0o077
            and not any(os.path.lexists(п / '.git') for п in (песочница, *песочница.parents)),
            'Разбор конфигурации требует приватный контекст вне Git')
    проверить_контекст()
    кэш = {}
    фиксированный = фиксированный_канал() if исполнитель is None else None
    def разобрать_конфиг(данные):
        отпечаток = хэш(данные)
        if отпечаток in кэш: return кэш[отпечаток]
        среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
        среда.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_SYSTEM=os.devnull,
            GIT_CONFIG_GLOBAL=os.devnull, GIT_PAGER='cat', GIT_TERMINAL_PROMPT='0')
        def вызвать(*аргументы):
            проверить_контекст()
            if фиксированный is not None:
                return фиксированный('config', '--file', '-', '--no-includes', '--null', *аргументы,
                    ввод=данные, рабочий_каталог=песочница, причина='Некорректная Git-конфигурация')
            процесс = subprocess.run([исполнитель, '--no-optional-locks', 'config', '--file', '-',
                '--no-includes', '--null', *аргументы], input=данные, capture_output=True,
                cwd=песочница, env=среда, timeout=30)
            ЧТЕНИЯ['ответов_Гит'] += 1; ЧТЕНИЯ['байтов_Гит'] += len(процесс.stdout)
            требовать(процесс.returncode == 0, 'Некорректная Git-конфигурация')
            return процесс.stdout
        записи = вызвать('--list')
        ключи = []
        запрещённые = ('filter.', 'include.', 'includeif.', 'extensions.', 'trace2.',
            'core.worktree', 'core.attributesfile', 'core.sparsecheckout', 'core.sshcommand',
            'core.autocrlf', 'core.eol', 'core.symlinks')
        for запись in записи.split(b'\0'):
            if not запись: continue
            ключ, _, значение = запись.partition(b'\n'); ключ = ключ.decode('utf-8').lower()
            требовать(ключ == 'extensions.worktreeconfig' or not ключ.startswith(запрещённые),
                'Преобразующая/перенаправляющая конфигурация')
            if ключ == 'codex.localenvironmentconfigpath':
                текст = значение.decode('utf-8')
                требовать(bool(текст) and (текст == '__none__' or Path(текст).is_absolute())
                    and not any(ord(ч) < 32 or ord(ч) == 127 for ч in текст), 'Неверная форма непрозрачного Codex-пути')
            ключи.append(ключ)
        if 'extensions.worktreeconfig' in ключи:
            значения = вызвать('--type=bool', '--get-all', 'extensions.worktreeConfig').split(b'\0')[:-1]
            требовать(значения and all(з in (b'true', b'false') for з in значения), 'Неверный флаг worktreeConfig')
        кэш[отпечаток] = ключи
        return ключи
    def проверить(корень):
        корень = путь(str(корень))
        админ, общий, указатели = физические_адреса(корень)
        слои = []
        for роль, файл in (('common', общий / 'config'), ('worktree', админ / 'config.worktree')):
            есть = os.path.lexists(файл)
            требовать(есть or роль == 'worktree', 'Отсутствует common config')
            данные = служебные_байты(файл) if есть else None
            if есть:
                ключи = разобрать_конфиг(данные)
                требовать(роль != 'worktree' or not any(к.startswith('extensions.') for к in ключи),
                    'Extension вне common config')
                требовать(служебные_байты(файл) == данные, 'Конфигурация изменилась при разборе')
            else:
                требовать(not os.path.lexists(файл), 'Конфигурация появилась при разборе')
            слои.append({'роль': роль, 'путь': str(файл), 'есть': есть,
                'sha256': хэш(данные) if есть else None})
        требовать(all(служебные_байты(п) == б for п, б in указатели.items()), 'Подмена Git-указателей')
        return {'админ': админ, 'общий': общий, 'слои': слои,
            'идентичности': {имя: [п.stat().st_dev, п.stat().st_ino, п.stat().st_mode]
                for имя, п in (('W', корень), ('admin', админ), ('common', общий))}}
    return проверить


def значимые_замки(с):
    for роль, корень, ветка, объект, общий in с['роли']:
        админ = с['ограда'](корень)['админ']
        for имя in ЗАМКИ_АДМИНА:
            требовать(not os.path.lexists(админ / имя), 'Значимый Git-замок: admin')
        for имя in ОПЕРАЦИИ_АДМИНА + (('MERGE_HEAD',) if роль == 'control' else ()):
            требовать(not os.path.lexists(админ / имя), 'Незавершённая операция защищённой роли')
        for имя in (ветка + '.lock', 'logs/' + ветка + '.lock'):
            путь(str(общий / имя))
            требовать(not os.path.lexists(общий / имя), 'Значимый Git-замок: ref')
    for общий in {с['ограда'](к)['общий'] for _, к in с['конфиг_роли']}:
        for имя in ЗАМКИ_ОБЩЕГО:
            путь(str(общий / имя))
            требовать(not os.path.lexists(общий / имя), 'Значимый Git-замок: common')


def свежая_конфигурация(с):
    записи = []
    for роль, корень in с['конфиг_роли']:
        физические = с['ограда'](корень)
        записи.append({'роль': роль, 'корень': str(корень), **физические,
            'админ': str(физические['админ']), 'общий': str(физические['общий'])})
    return хэш(байты(записи))


def адреса(корень, читать, *, ограда=None):
    админ = путь(читать(корень, 'rev-parse', '--absolute-git-dir').decode().strip())
    общий = Path(читать(корень, 'rev-parse', '--git-common-dir').decode().strip())
    общий = путь(str(общий if общий.is_absolute() else корень / общий))
    объекты = путь(str(общий / 'objects'))
    for область in (админ, общий, объекты):
        сведения = область.stat()
        требовать(stat.S_ISDIR(сведения.st_mode) and сведения.st_uid == os.getuid()
            and not сведения.st_mode & 0o022, 'Чужая или общедоступная Git-область')
    for файл in ('shallow', 'info/grafts', 'objects/info/alternates'):
        требовать(not os.path.lexists(общий / файл), 'Неполная/перенаправленная Git-база')
    if ограда is None:
        for область in {админ, общий}:
            требовать(not any(область.rglob('*.lock')), 'Git-замок или незавершённая операция')
        конфигурация = читать(корень, 'config', '--local', '--null', '--list')
        запрещённые = ('filter.', 'include.', 'includeif.', 'extensions.', 'trace2.',
            'core.worktree', 'core.attributesfile', 'core.sparsecheckout', 'core.sshcommand',
            'core.autocrlf', 'core.eol', 'core.symlinks')
        for запись in конфигурация.split(b'\0'):
            ключ = запись.split(b'\n', 1)[0].decode().lower()
            требовать(not ключ.startswith(запрещённые), 'Преобразующая/перенаправляющая конфигурация')
    else:
        физические = ограда(корень)
        требовать((админ, общий) == (физические['админ'], физические['общий']), 'Git перенаправил физические адреса')
        конфигурация = байты(физические['слои'])
    ЧТЕНИЯ['проверок_замен'] += 1
    требовать(not читать(корень, 'for-each-ref', '--format=%(refname)', 'refs/replace'), 'Replace refs запрещены')
    for область in {админ, общий}:
        атрибуты = область / 'info/attributes'
        требовать(not os.path.lexists(атрибуты), 'Локальные атрибуты не входят в проверенный checkout')
    return админ, общий, объекты, хэш(конфигурация)



def версия(вход):
    требовать(type(вход) is dict, 'Вход подготовки должен быть объектом JSON')
    требовать(вход.get('схема') in ('fum.вход-подготовки-кандидата.1',
        'fum.вход-подготовки-кандидата.2'), 'Подготовка не является Creator/D/приёмкой')
    return вход['схема'][-1]


def схема(вход, имя):
    return 'fum.' + имя + '.' + версия(вход)


def сверить_версию_плана(вход, описание):
    требовать(type(описание) is dict, 'План должен быть объектом JSON')
    требовать(описание.get('схема') == схема(вход, 'план-подготовки-кандидата'), 'Смешение версий входа и плана')
    до = описание.get('исходный_снимок')
    требовать(type(до) is dict and (('refs_sha256' in до and 'защищённые_ссылки' not in до)
        if версия(вход) == '1' else ('защищённые_ссылки' in до and 'refs_sha256' not in до)),
        'Смешение версий снимка ссылок')


def защищённые_ссылки(с):
    """Ровно B/control из проверенных ACT/assignment, семантика direct refs."""
    читать = с['читать']
    требовать(читать(с['корень'], 'symbolic-ref', 'HEAD').decode().strip() == с['роли'][0][2],
        'HEAD больше не является выбранной веткой B')
    итог = []
    for роль, корень, ветка, объект, общая_база in с['роли']:
        общий = Path(читать(корень, 'rev-parse', '--git-common-dir').decode().strip())
        общий = путь(str(общий if общий.is_absolute() else корень / общий))
        требовать(общий == общая_база, 'Физическая Git-база роли изменилась')
        ЧТЕНИЯ['защит_ссылок'] += 1
        записи = [строка.split(b'\0') for строка in читать(корень, 'for-each-ref',
            '--format=%(refname)%00%(objectname)%00%(symref)', ветка).splitlines()]
        требовать(записи == [[ветка.encode(), объект.encode(), b'']],
            'Защищённая ссылка отсутствует, изменилась или стала symbolic: ' + роль)
        итог.append({'роль': роль, 'гит_база': str(общий), 'ветка': ветка, 'коммит': объект, 'тип': 'прямая',
            'идентичность_базы': [общий.stat().st_dev, общий.stat().st_ino, общий.stat().st_mode]})
    return итог


def контекст(вход, назначение):
    поля(вход, {'схема', 'параметры_базиса', 'выбор_базиса', 'код', 'код_подготовки_sha256', 'нативный', 'состояние'})
    версия(вход)
    требовать(хэш(прочитать(Path(__file__).resolve())) == вход['код_подготовки_sha256'], 'Подменён код подготовки')
    ограда = (ограда_конфигурации(вход['состояние']) if версия(вход) == '2' else None)
    акт_подготовки = прочитать_назначение(вход['выбор_базиса']['отчётный_корень'], назначение, ограда=ограда)
    поля(акт_подготовки, {'схема', 'вход_sha256', 'координатор', 'исполнитель', 'ACT_B', 'контроль'})
    требовать(акт_подготовки['схема'] == 'fum.поручение-подготовки-кандидата.1'
        and акт_подготовки['вход_sha256'] == хэш(байты(вход)), 'Нет независимого поручения подготовки')
    выбор = вход['выбор_базиса']
    if ограда is not None:
        поля(выбор['гит'], {'путь', 'sha256'})
        требовать(хэш(прочитать(выбор['гит']['путь'], двоичный=True)) == выбор['гит']['sha256'], 'Подменён runtime')
        ограда = ограда_конфигурации(вход['состояние'], выбор['гит']['путь'])
        закреплённый = выбор['вход_построителя']
        сырые = прочитать(закреплённый['путь'])
        требовать(хэш(сырые) == закреплённый['sha256'], 'Подменён вход построителя до Git')
        ранний_источник = путь(разобрать(сырые)['корень'])
        for база in (путь(вход['параметры_базиса']['корень']), путь(выбор['отчётный_корень']), ранний_источник):
            ограда(база)
    создатель, допуск, построитель = загрузить_код(вход['код'])
    читать = канал_гита(выбор, создатель, допуск, ограда=ограда)
    отчёт = путь(выбор['отчётный_корень'])
    требовать(разобрать(допуск.прочитать_блоб_базиса(отчёт, назначение, читать, создатель)) == акт_подготовки,
        'ROOT blob изменился после bootstrap')
    параметры = вход['параметры_базиса']
    (корень, _, _, _, _, акт, предмет, происхождение, вход_построителя,
        защиты, _) = допуск.контекст_назначения_базиса(параметры, выбор, создатель)
    требовать(акт_подготовки['координатор'] == акт['координатор']
        and акт_подготовки['исполнитель'] == акт['исполнитель']
        and акт_подготовки['ACT_B'] == выбор['назначение']
        and акт_подготовки['контроль'] == акт['контроль'], 'Чужое конечное назначение подготовки')
    допуск.поля_базиса(акт['контроль'], {'ветка', 'коммит'})
    требовать(читать(отчёт, 'show-ref', '--verify', '--hash', акт['контроль']['ветка']).decode().strip()
        == акт['контроль']['коммит'], 'Контрольное поколение изменилось')
    поля(вход['нативный'], {'путь', 'sha256', 'байты'})
    нативные = прочитать(вход['нативный']['путь'])
    требовать(хэш(нативные) == вход['нативный']['sha256'] and len(нативные) == вход['нативный']['байты'],
        'Подменён native подготовки')
    обычное = importlib.import_module('обычное_поручение')
    начало, наблюдение, _ = обычное.постановка.прочитать_начало_источника(путь(вход['нативный']['путь']))
    поручение = обычное.постановка.прочитать_нативное_поручение(путь(вход['нативный']['путь']), кодирование='буквальный')
    требовать(начало.get('id') == акт['исполнитель'] and начало.get('thread_source') == 'agent_created_thread'
        and начало.get('cwd') == наблюдение.get('cwd') == str(корень)
        and начало.get('git', {}).get('commit_hash') == предмет['K']
        and поручение['отправитель'] == акт['координатор']
        and хэш(поручение['текст'].encode()) == акт['хэш_нативного_поручения'], 'Чужой actor/native/birth')
    for имя in ('гит', 'python'):
        поля(выбор[имя], {'путь', 'sha256'})
        требовать(хэш(прочитать(выбор[имя]['путь'], двоичный=True)) == выбор[имя]['sha256'], 'Подменён runtime')
    требовать(Path(sys.executable).resolve() == путь(выбор['python']['путь']), 'Другой Python runtime')
    админ, общий, объекты, конфиг = адреса(корень, читать, ограда=ограда)
    _, отчётный_общий, _, _ = адреса(отчёт, читать, ограда=ограда)
    источник = путь(вход_построителя['корень'])
    if источник != корень: адреса(источник, читать, ограда=ограда)
    состояние = путь(вход['состояние'])
    требовать(состояние.is_dir() and состояние.stat().st_uid == os.getuid()
        and состояние.stat().st_mode & 0o077 == 0
        and not any(os.path.lexists(п / '.git') for п in (состояние, *состояние.parents))
        and all(not состояние.is_relative_to(п) and not п.is_relative_to(состояние)
            for п in (корень, админ, общий, путь(вход_построителя['каталог_объектов']))), 'Неприватная/пересекающаяся область намерения')
    требовать({п.name for п in состояние.iterdir()} <= {'замок', 'намерение.json', 'квитанция.json'}, 'Неизвестный остаток подготовки')
    for файл in состояние.iterdir():
        прочитать(файл)
        требовать(файл.stat().st_uid == os.getuid() and not файл.stat().st_mode & 0o077, 'Неприватное состояние подготовки')
    _, частные, _, листья, _ = построитель.рассчитать(вход_построителя, происхождение['выбор_решений'])
    дерево, деревья = построитель.сериализовать_деревья(листья)
    найденные = {}
    for префикс in частные.iterdir():
        for файл in префикс.iterdir():
            объект = префикс.name + файл.name
            найденные[объект] = построитель.прочитать_сжатый_объект(файл, объект)
    требовать(найденные == деревья and дерево == предмет['дерево'], 'Частная ODB не равна полному пересчитанному T')
    блобы = {}
    базис = importlib.import_module('приём_базиса_состояния_узла')
    with базис.ПакетСырыхОбъектов(корень) as пакет:
        for режим, тип, объект in листья.values():
            if тип == 'blob':
                пакет.прочитать(объект, 'blob')
                блобы[объект] = пакет.метаданные[объект]['байты']
    for имя, запись in листья.items():
        if Path(имя).name == '.gitattributes':
            данные = читать(корень, 'cat-file', 'blob', запись[2])
            требовать(not any(строка.strip() and not строка.lstrip().startswith(b'#')
                for строка in данные.splitlines()), 'Преобразующие атрибуты T требуют отдельного допуска')
    for объект in деревья:
        префикс = объекты / объект[:2]
        if os.path.lexists(префикс):
            путь(str(префикс))
            сведения = префикс.stat()
            требовать(stat.S_ISDIR(сведения.st_mode) and сведения.st_uid == os.getuid()
                and not сведения.st_mode & 0o022, 'Перенаправленный префикс обычной ODB')
            файл = префикс / объект[2:]
            if os.path.lexists(файл): прочитать(файл)
    с = {'читать': читать, 'корень': корень, 'админ': админ, 'общий': общий, 'объекты': объекты,
        'конфиг': конфиг, 'состояние': состояние, 'предмет': предмет, 'защиты': защиты,
        'листья': листья, 'деревья': деревья, 'блобы': блобы, 'частные': частные, 'допуск': допуск,
        'назначение': назначение, 'ветка': параметры['ветка'], 'вход': вход}
    if версия(вход) == '2':
        требовать(источник == ранний_источник, 'Дрейф роли источника')
        с['ограда'] = ограда
        с['конфиг_роли'] = [('B', корень), ('control', отчёт), ('source', источник)]
        с['роли'] = [('B', корень, акт['адрес']['ветка'], предмет['K'], общий),
            ('control', отчёт, акт['контроль']['ветка'], акт['контроль']['коммит'], отчётный_общий)]
        защищённые_ссылки(с)
        значимые_замки(с)
        с['конфиг'] = свежая_конфигурация(с)
    return с


def инвентарь(с):
    читать, корень = с['читать'], с['корень']
    сырые = читать(корень, 'ls-files', '--stage', '-v', '-z')
    требовать(сырые.endswith(b'\0'), 'Незавершённый индекс')
    записи = {}
    for строка in сырые.split(b'\0')[:-1]:
        мета, имя = строка.split(b'\t', 1)
        флаг, режим, объект, стадия = мета.decode().split(' ')
        имя = с['допуск'].имя_индекса(имя)
        требовать(флаг == 'H' and стадия == '0' and имя not in записи, 'Неполный/скрывающий индекс')
        записи[имя] = (режим, 'commit' if режим == '160000' else 'blob', объект)
    return записи


def рабочие_файлы(с, ожидаемые):
    корень, читать = с['корень'], с['читать']
    итог, регистр = {}, {}
    for каталог, подкаталоги, файлы in os.walk(корень, followlinks=False):
        for имя in list(подкаталоги) + файлы:
            файл = Path(каталог) / имя
            относительный = str(файл.relative_to(корень))
            if относительный == '.git':
                if имя in подкаталоги: подкаталоги.remove(имя)
                continue
            требовать(unicodedata.normalize('NFC', относительный) == относительный
                and регистр.setdefault(относительный.casefold(), относительный) == относительный,
                'Unicode/регистровая коллизия W')
            сведения = файл.lstat()
            запись = ожидаемые.get(относительный)
            if запись and запись[0] == '160000':
                требовать(stat.S_ISDIR(сведения.st_mode), 'Перенаправленный gitlink')
                if имя in подкаталоги: подкаталоги.remove(имя)
                итог[относительный] = ['160000', запись[2]]
            elif stat.S_ISDIR(сведения.st_mode):
                требовать(any(п.startswith(относительный + '/') for п in ожидаемые), 'Неучтённый каталог W')
            elif запись and запись[0] == '120000':
                требовать(stat.S_ISLNK(сведения.st_mode), 'Историческая ссылка заменена')
                данные = os.fsencode(os.readlink(файл))
                требовать(с['допуск'].объект_по_байтам('blob', данные) == запись[2], 'Подменена историческая ссылка')
                итог[относительный] = ['120000', хэш(данные)]
            else:
                требовать(запись and запись[0] in ('100644', '100755'), 'Untracked/ignored/специальная коллизия W')
                данные = прочитать(файл)
                режим = '100755' if сведения.st_mode & stat.S_IXUSR else '100644'
                требовать(режим == запись[0] and с['допуск'].объект_по_байтам('blob', данные) == запись[2], 'Dirty bytes/mode W')
                итог[относительный] = [режим, хэш(данные)]
    for имя, запись in ожидаемые.items():
        if запись[0] == '160000' and not os.path.lexists(корень / имя):
            итог[имя] = ['160000', запись[2]]
    требовать(set(итог) == set(ожидаемые), 'W не равен полному индексу')
    return итог


def снимок(с, *, итог=False):
    читать, корень = с['читать'], с['корень']
    записи = инвентарь(с)
    for имя in ('CHERRY_PICK_HEAD', 'REVERT_HEAD', 'rebase-merge', 'rebase-apply', 'BISECT_LOG', 'sequencer'):
        требовать(not os.path.lexists(с['админ'] / имя), 'Посторонняя незавершённая Git-операция')
    if итог:
        требовать(записи == с['листья'], 'Индекс не равен T')
    else:
        требовать(not читать(корень, 'status', '--porcelain', '--untracked-files=all'), 'Dirty исходное дерево')
        требовать(читать(корень, 'rev-parse', 'HEAD').decode().strip() == с['предмет']['K'], 'Исходный HEAD не K')
        for имя in ('MERGE_HEAD', 'CHERRY_PICK_HEAD', 'REVERT_HEAD', 'rebase-merge', 'rebase-apply', 'BISECT_LOG', 'sequencer'):
            требовать(not os.path.lexists(с['админ'] / имя), 'Незавершённая Git-операция')
    файлы = рабочие_файлы(с, записи)
    итоговый = {'HEAD': читать(корень, 'rev-parse', 'HEAD').decode().strip(),
        'ref': читать(корень, 'symbolic-ref', 'HEAD').decode().strip(),
        'индекс_sha256': хэш(прочитать(с['админ'] / 'index')), 'файлы': файлы,
        'конфиг_sha256': с['конфиг'], 'админ': str(с['админ']), 'общий': str(с['общий']),
        'адреса': {str(п): [п.stat().st_dev, п.stat().st_ino, п.stat().st_mode]
            for п in {корень, с['админ'], с['общий'], с['состояние'], с['частные']}},
        'частные_объекты': {str(п.relative_to(с['частные'])): list(осмотр(п.stat())) + [хэш(прочитать(п))]
            for п in с['частные'].rglob('*') if п.is_file()},
        'указатели': {str(п): хэш(прочитать(п)) for п in (корень / '.git', с['админ'] / 'commondir', с['админ'] / 'gitdir')
            if п.is_file()}}
    if версия(с['вход']) == '1':
        итоговый['refs_sha256'] = хэш(читать(корень, 'for-each-ref', '--format=%(refname) %(objectname)'))
    else:
        значимые_замки(с)
        итоговый['конфиг_sha256'] = свежая_конфигурация(с)
        итоговый['защищённые_ссылки'] = защищённые_ссылки(с)
    return итоговый


def отсутствующие_деревья(с):
    return с['читать'].деревья(с['корень'], с['деревья'], с['объекты'])

def план(вход, назначение):
    with фаза('план') as учёт:
        с = контекст(вход, назначение)
        требовать(not os.path.lexists(с['состояние'] / 'намерение.json'), 'Сначала разберите прежнее намерение')
        до = снимок(с)
        прежние = инвентарь(с)
        for имя in set(прежние) | set(с['листья']):
            записи = (прежние.get(имя), с['листья'].get(имя))
            if any(з and з[0] in ('120000', '160000') for з in записи):
                требовать(записи[0] == записи[1], 'Подготовка не меняет историческую специальную запись')
        отсутствуют = отсутствующие_деревья(с)
        учёт.update(деревьев=len(с['деревья']), блобов=len(с['блобы']),
            байтов_предмета=sum(map(len, с['деревья'].values())) + sum(с['блобы'].values()))
        требовать(снимок(с) == до, 'Дрейф при планировании')
        return {'схема': схема(вход, 'план-подготовки-кандидата'), 'назначение': назначение,
            'вход_sha256': хэш(байты(вход)), 'исходный_снимок': до,
            'предмет': с['предмет'], 'защиты': с['защиты'], 'отсутствующие_деревья': отсутствуют,
            'объекты': {'деревьев': len(с['деревья']), 'байтов_деревьев': sum(map(len, с['деревья'].values())),
                'блобов': len(с['блобы']), 'байтов_блобов': sum(с['блобы'].values())}}


def сверить_выбор(с, выбранный, описание_плана):
    документ = разобрать(с['допуск'].прочитать_блоб_базиса(путь(с['вход']['выбор_базиса']['отчётный_корень']),
        выбранный, с['читать'], importlib.import_module('создание_коммита')))
    поля(документ, {'схема', 'назначение', 'план_sha256'})
    требовать(документ == {'схема': 'fum.выбор-применения-кандидата.1', 'назначение': с['назначение'],
        'план_sha256': хэш(байты(описание_плана))}, 'Нет независимого выбора точного плана')


def синхронизировать(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try: os.fsync(дескриптор)
    finally: os.close(дескриптор)


def установить(файл, данные, *, впервые=False):
    путь(str(файл.parent))
    временный = файл.parent / ('.подготовка-' + uuid.uuid4().hex)
    with os.fdopen(os.open(временный, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600), 'wb') as поток:
        поток.write(данные); поток.flush(); os.fsync(поток.fileno())
    if впервые:
        os.link(временный, файл, follow_symlinks=False)
        os.unlink(временный)
    else:
        прочитать(файл)
        os.replace(временный, файл)
    синхронизировать(файл.parent)


def проверить(вход, назначение, описание_плана, выбранный):
    сверить_версию_плана(вход, описание_плана)
    with фаза('финальная-сверка') as учёт:
        с = контекст(вход, назначение)
        учёт.update(деревьев=len(с['деревья']), блобов=len(с['блобы']),
            байтов_предмета=sum(map(len, с['деревья'].values())) + sum(с['блобы'].values()))
        сверить_выбор(с, выбранный, описание_плана)
        требовать(описание_плана['вход_sha256'] == хэш(байты(вход))
            and описание_плана['предмет'] == с['предмет'] and описание_плана['защиты'] == с['защиты'], 'Подменён план')
        индекс = с['допуск'].сверить_индекс_базиса(с['корень'], с['предмет'], с['защиты'], с['читать'])
        после = снимок(с, итог=True)
        до = описание_плана['исходный_снимок']
        требовать(all(после[к] == до[к] for к in ('HEAD', 'ref', 'refs_sha256' if версия(вход) == '1' else 'защищённые_ссылки', 'конфиг_sha256', 'админ', 'общий', 'адреса', 'указатели', 'частные_объекты')),
            'Изменились защищённые HEAD/ref/config/адреса')
        требовать(not отсутствующие_деревья(с), 'T всё ещё не материализован')
        return {'схема': схема(вход, 'проверка-подготовленного-кандидата'), 'план_sha256': хэш(байты(описание_плана)),
            'выбор': выбранный, 'предмет': с['предмет'], 'индекс_sha256': индекс, 'снимок': после}


def применить(вход, назначение, описание_плана, выбранный, *, остановка=None):
    сверить_версию_плана(вход, описание_плана)
    with фаза('допуск'):
        с = контекст(вход, назначение)
        сверить_выбор(с, выбранный, описание_плана)
    состояние = с['состояние']
    дескриптор = os.open(состояние / 'замок', os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW | os.O_NONBLOCK, 0o600)
    try:
        сведения = os.fstat(дескриптор)
        требовать(stat.S_ISREG(сведения.st_mode) and сведения.st_nlink == 1 and сведения.st_uid == os.getuid(), 'Чужой замок')
        fcntl.flock(дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
        def сторож():
            with фаза('повторный-допуск') as учёт:
                требовать(осмотр(os.fstat(дескриптор)) == осмотр((состояние / 'замок').lstat()), 'Замок подменён')
                новый = контекст(вход, назначение)
                if версия(вход) == '2':
                    требовать(защищённые_ссылки(новый) == описание_плана['исходный_снимок']['защищённые_ссылки'],
                        'Дрейф физических защищённых ролей')
                    требовать(новый['конфиг'] == описание_плана['исходный_снимок']['конфиг_sha256'],
                        'Дрейф конфигурации Git')
                сверить_выбор(новый, выбранный, описание_плана)
                for п, ожидаемые in описание_плана['исходный_снимок']['адреса'].items():
                    файл = путь(п)
                    требовать([файл.stat().st_dev, файл.stat().st_ino, файл.stat().st_mode] == ожидаемые, 'Заменена закреплённая область')
                учёт.update(деревьев=len(новый['деревья']), блобов=len(новый['блобы']),
                    байтов_предмета=sum(map(len, новый['деревья'].values())) + sum(новый['блобы'].values()))
                return новый
        намерение, квитанция = состояние / 'намерение.json', состояние / 'квитанция.json'
        привязка = {'план_sha256': хэш(байты(описание_плана)), 'выбор': выбранный}
        if os.path.lexists(намерение) or os.path.lexists(квитанция):
            with фаза('повтор'):
                запись = разобрать(прочитать(намерение))
                требовать(запись == {**привязка, 'схема': схема(вход, 'намерение-подготовки-кандидата'), 'фаза': 'завершено'},
                    'Незавершённый/неизвестный исход; слепой повтор запрещён')
                ожидаемая = проверить(вход, назначение, описание_плана, выбранный)
                требовать(прочитать(квитанция) == байты(ожидаемая), 'Квитанция утрачена или подменена')
                сторож()
                return {**ожидаемая, 'без_повторных_эффектов': True}
        требовать(план(вход, назначение) == описание_плана, 'Исходный снимок/план изменился')
        def отметить(имя, *, впервые=False):
            сторож()
            установить(намерение, байты({**привязка, 'схема': схема(вход, 'намерение-подготовки-кандидата'), 'фаза': имя}), впервые=впервые)
        def граница(имя):
            if остановка is not None: остановка(имя)
            сторож()
        отметить('намерение', впервые=True)
        граница('после-намерения')
        отметить('до-импорта')
        with фаза('импорт') as учёт:
            for объект in описание_плана['отсутствующие_деревья']:
                сторож()
                требовать(снимок(с) == описание_плана['исходный_снимок'], 'Дрейф до импорта')
                if объект in отсутствующие_деревья(с):
                    ответ = с['читать'](с['корень'], 'hash-object', '-t', 'tree', '-w', '--stdin', ввод=с['деревья'][объект])
                    требовать(ответ.strip().decode() == объект, 'Импорт вернул другой OID')
                    учёт['деревьев'] += 1
                    учёт['байтов_предмета'] += len(с['деревья'][объект])
                    файл = с['объекты'] / объект[:2] / объект[2:]
                    with файл.open('rb') as поток: os.fsync(поток.fileno())
                    синхронизировать(файл.parent); синхронизировать(с['объекты'])
            требовать(not отсутствующие_деревья(с), 'Неполный импорт T')
        отметить('импортирован')
        граница('после-импорта')
        отметить('до-ref-HEAD')
        with фаза('ref-HEAD'):
            требовать(снимок(с) == описание_плана['исходный_снимок'], 'Дрейф перед Git-установкой')
            # Собственный ref создан владельцем при запуске и уже равен K.
            # Повторная установка того же значения не нужна.
            требовать(с['читать'](с['корень'], 'show-ref', '--verify', '--hash', с['ветка']).decode().strip()
                == с['предмет']['K'], 'Собственный ref больше не равен K')
        отметить('ref-HEAD-проверены')
        граница('после-ref-HEAD')
        отметить('до-индекса-файлов')
        with фаза('индекс-файлы') as учёт:
            требовать(снимок(с) == описание_плана['исходный_снимок'], 'Дрейф перед checkout')
            с['читать'](с['корень'], 'read-tree', '-m', '-u', с['предмет']['K'], с['предмет']['дерево'])
            if версия(вход) == '2': граница('после-read-tree')
            установить(с['админ'] / 'MERGE_HEAD', (с['предмет']['R'] + '\n').encode(), впервые=True)
            with (с['админ'] / 'index').open('rb') as поток: os.fsync(поток.fileno())
            каталоги = {с['корень']}
            for имя, запись in с['листья'].items():
                файл = с['корень'] / имя
                if запись[0] in ('100644', '100755'):
                    with файл.open('rb') as поток: os.fsync(поток.fileno())
                for родитель in файл.parents:
                    if not родитель.is_relative_to(с['корень']): break
                    каталоги.add(родитель)
            for каталог in sorted(каталоги, key=lambda п: len(п.parts), reverse=True): синхронизировать(каталог)
            синхронизировать(с['админ'])
            учёт.update(деревьев=len(с['деревья']), блобов=len(с['блобы']), байтов_предмета=sum(с['блобы'].values()))
        отметить('индекс-файлы-установлены')
        граница('после-индекса-файлов')
        результат = проверить(вход, назначение, описание_плана, выбранный)
        отметить('до-квитанции')
        граница('перед-квитанцией')
        with фаза('квитанция'):
            требовать(проверить(вход, назначение, описание_плана, выбранный) == результат, 'Поздний дрейф candidate')
            установить(квитанция, байты(результат), впервые=True)
            требовать(проверить(вход, назначение, описание_плана, выбранный) == результат
                and прочитать(квитанция) == байты(результат), 'Дрейф при публикации квитанции')
            отметить('завершено')
        return {**результат, 'без_повторных_эффектов': False}
    finally:
        os.close(дескриптор)


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('действие', choices=('план', 'применить', 'проверить'))
    разбор.add_argument('--вход', required=True)
    разбор.add_argument('--назначение', required=True, help='Независимый selector ROOT, отдельный от candidate')
    разбор.add_argument('--план')
    разбор.add_argument('--выбор')
    разбор.add_argument('--профиль', action='store_true')
    параметры = разбор.parse_args()
    def аудит(событие, аргументы):
        global ПРОЦЕССЫ, ЭФФЕКТЫ_ГИТ
        if событие == 'subprocess.Popen':
            ПРОЦЕССЫ += 1
            команда = аргументы[1]
            if any(имя in команда for имя in ('read-tree', 'checkout', 'reset', 'update-ref')) or ('hash-object' in команда and '-w' in команда):
                ЭФФЕКТЫ_ГИТ += 1
    sys.addaudithook(аудит)
    try:
        вход = разобрать(прочитать(параметры.вход))
        назначение = разобрать(прочитать(параметры.назначение))
        if параметры.действие == 'план':
            результат = план(вход, назначение)
        else:
            требовать(параметры.план and параметры.выбор, 'Нужны точный план и независимый выбор')
            описание = разобрать(прочитать(параметры.план))
            выбор = разобрать(прочитать(параметры.выбор))
            результат = (применить if параметры.действие == 'применить' else проверить)(вход, назначение, описание, выбор)
        sys.stdout.buffer.write(байты(результат))
        return 0
    except (ValueError, OSError, KeyError, TypeError, subprocess.SubprocessError, zlib.error) as ошибка:
        print(str(ошибка), file=sys.stderr)
        return 2
    finally:
        if параметры.профиль:
            дочерние = resource.getrusage(resource.RUSAGE_CHILDREN)
            print(байты({'фазы': ПРОФИЛЬ, 'процессов': ПРОЦЕССЫ,
                'ЦПУ_процесса_наносекунды': time.process_time_ns(),
                'ЦПУ_дочерних_наносекунды': round(1e9 * (дочерние.ru_utime + дочерние.ru_stime)),
                'эффекты_Гит': ЭФФЕКТЫ_ГИТ, 'чтения': dict(ЧТЕНИЯ),
                'пакетный_канал_деревьев': {**ПАКЕТНЫЕ_ДЕРЕВЬЯ,
                    'байтов_неразобранных': ПАКЕТНЫЕ_ДЕРЕВЬЯ['байтов_вывода'] - sum(ПАКЕТНЫЕ_ДЕРЕВЬЯ[к]
                        for к in ('байтов_заголовков', 'байтов_содержимого', 'байтов_разделителей'))},
                'память': {'пик_резидентной_памяти_процесса_байтов':
                    resource.getrusage(resource.RUSAGE_SELF).ru_maxrss * (1 if sys.platform == 'darwin' else 1024),
                    'граница': 'Пик процесса по ОС; память всех детей и физический I/O не измерены.'}}).decode().strip(), file=sys.stderr)


if __name__ == '__main__':
    sys.exit(выполнить())

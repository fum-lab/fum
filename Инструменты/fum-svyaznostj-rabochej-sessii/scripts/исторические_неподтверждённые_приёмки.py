def хэш_объекта(значение):
    байты = (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")
    return hashlib.sha256(байты).hexdigest()


def историческая_неподтверждённая_связь(приёмка, доказательство):
    """Распознать только закреплённый отказ; не выдавать его за успешный этап."""
    if not isinstance(приёмка, dict) or not isinstance(доказательство, dict):
        return False
    коммит = приёмка.get("коммит")
    связь = доказательство.get("связь")
    if (
        not isinstance(коммит, str)
        or коммит not in НЕПОДТВЕРЖДЁННЫЕ_V3
        or not isinstance(связь, dict)
        or доказательство.get("состояние") != "не подтверждён"
        or связь.get("состояние") != "не восстановлен"
        or доказательство.get("коммит") != коммит
        or связь.get("коммит") != коммит
        or доказательство.get("сессия") != приёмка.get("запрос")
        or доказательство.get("финальный_запуск") != приёмка.get("финальный_запуск")
    ):
        return False
    return (хэш_объекта(приёмка), хэш_объекта(доказательство)) == НЕПОДТВЕРЖДЁННЫЕ_V3[коммит]

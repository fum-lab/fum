"""A.3 связывает исторические R/P.2 с новым H, T и контрольным поколением.

Чтение не устанавливает Журнал и не заменяет независимый ACT.3.
Прежние A.1/A.2 сохраняют собственные версии и ограничения.
"""
import полномочия_ветки_состояния_узла as прежние
import проверенные_повторные_полномочия_узла as исторические
import проверенный_повторный_план_состояния as планы
import цели_ветки_состояния_узла as цели

СХЕМА = 'fum.полномочия-ветки-состояния-узла.3'
СХЕМА_АКТА = 'fum.поручение-дочерней-контрольной-точки.3'
ПРЕДЕЛ = 1024 * 1024
ПОЛЯ = исторические.ПОЛЯ
гит = прежние.гит
требовать = прежние.требовать


def сверить_проект(данные, *, корень):
    """Проверить тело A.3; незакреплённый проект не разрешает эффект."""
    try:
        корень = гит.физический_корень(корень)
        требовать(type(данные) is bytes and 0 < len(данные) <= ПРЕДЕЛ,
            'граница повторных полномочий — один МиБ')
        документ = прежние.разобрать(данные)
        прежние.поля(документ, ПОЛЯ)
        требовать(документ['схема'] == СХЕМА, 'нужна отдельная схема A.3')
        # Используются только общие структурные проверки. Эта временная копия
        # не является независимо выбранным A.1 и не передаётся его эффектам.
        общие = {ключ: значение for ключ, значение in документ.items() if ключ != 'план_журнала'}
        общие['схема'] = прежние.СХЕМА
        прежние._сверить_состав(корень, общие, None, новый_эффект=False)
        цели.уникальные(документ['цели'])
        проверенный = планы.прочитать(документ['план_журнала'], корень=корень)
        план = проверенный['документ']
        for имя in (прежние.ИДЕНТИЧНОСТЬ - {'поколение_полномочий'}) | {
                'ветка', 'хэш_корня', 'исходный_коммит'}:
            требовать(документ[имя] == план[имя], 'A.3 и P.2 расходятся: ' + имя)
        требовать(документ['поколение_полномочий'] != план['поколение_полномочий'],
            'повторный эффект требует нового поколения полномочий')
        требовать(документ['начальный_коммит'] == план['первоначальный_запрос']['коммит'],
            'A.3 потерял первоначальную постановку')
        требовать(документ['путь'] == план['доверие']['источник']['путь'],
            'A.3 выбирает другой expected')
        требовать({файл['путь'] for файл in план['файлы']} <= set(документ['цели']),
            'T не содержит точную новую пару P.2')
        требовать(гит.предок(корень, документ['исходный_коммит'],
            документ['план_журнала']['коммит']), 'H не предшествует закреплённому P.2')
        return {'документ': документ, 'байты': данные, 'sha256': прежние.хэш(данные),
            'план_журнала': {'источник': документ['план_журнала'], 'значение': план},
            'разрешение_установки': False}
    except исторические._ошибки() as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def прочитать(корень, выбор, *, новый_эффект=True):
    """Прочитать независимый Git blob A.3, сохраняя строгий порядок P < A."""
    try:
        корень = гит.физический_корень(корень)
        исторические.канон.источник(выбор)
        гит.полный_объект(корень, выбор['коммит'])
        размер = int(гит.гит(корень, 'cat-file', '-s', выбор['коммит'] + ':' + выбор['путь']))
        требовать(0 < размер <= ПРЕДЕЛ, 'повторные полномочия превышают границу чтения')
        данные = гит.объект_файла(корень, выбор['коммит'], выбор['путь'])
        требовать(прежние.хэш(данные) == выбор['sha256'], 'подмена Git-полномочий A.3')
        итог = сверить_проект(данные, корень=корень)
        документ = итог['документ']
        исторические.проверить_порядок(корень, документ['план_журнала']['коммит'], выбор['коммит'])
        if новый_эффект:
            требовать(гит.гит(корень, 'rev-parse', '--verify', документ['контрольная_ветка'])
                == выбор['коммит'], 'изменилось контрольное поколение повторных полномочий')
        return итог
    except исторические._ошибки() as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def проверить_акт(корень, акт, *, новый_эффект=True, коммит_акта=None):
    """ACT.3 выбирается вызывающим читателем отдельно от копии maker."""
    прежние.поля(акт, {'схема', 'координатор', 'исполнитель', 'ветка', 'область',
        'постановка', 'хэш_нативного_поручения', 'полномочия_узла'})
    требовать(акт['схема'] == СХЕМА_АКТА, 'A.3 требует отдельный ACT.3')
    итог = прочитать(корень, акт['полномочия_узла'], новый_эффект=новый_эффект)
    документ = итог['документ']
    требовать(акт['ветка'] == документ['ветка']
        and акт['координатор'] == документ['координатор']
        and акт['исполнитель'] == документ['владелец']
        and акт['постановка']['коммит'] == документ['начальный_коммит']
        and акт['область'] == документ['цели'], 'ACT.3 не соответствует A.3')
    if коммит_акта is not None:
        исторические.проверить_порядок(корень, акт['полномочия_узла']['коммит'], коммит_акта)
    return документ


def проверить_дерево(корень, владелец, ветка, выбор, *, исходный_коммит=None,
                     цели=None, новый_эффект=True):
    """Новый эффект требует собственной физической state-ветки и точного T."""
    документ = прочитать(корень, выбор, новый_эффект=новый_эффект)['документ']
    корень = гит.физический_корень(корень)
    требовать(ветка == прежние.ВЕТКА and владелец == документ['владелец']
        and прежние.хэш(str(корень).encode()) == документ['хэш_корня'],
        'дерево, UUID или state ref отличаются от A.3')
    if исходный_коммит is not None:
        требовать(исходный_коммит == документ['исходный_коммит'], 'другая исходная база A.3')
    if цели is not None:
        требовать(цели == документ['цели'], 'изменился точный упорядоченный T повторного этапа')
    return документ

"""Чтение подготовленного merge без write-tree, commit и разрешения записи."""
import hashlib
import os
from pathlib import Path

from контракт_обратного_приёма import _ветка
from наблюдение_обратного_приёма import (
    _адрес_гит, _без_внешних_фильтров, _ветки, _гит, _текст, _требовать,
)


def _основания(корень, получатель, источник):
    _ветки(корень, получатель, источник)
    for имя, ожидаемое in (("MERGE_HEAD", источник["коммит"]),
                           ("ORIG_HEAD", получатель["коммит"])):
        путь = _адрес_гит(корень, имя)
        _требовать(not путь.is_symlink() and путь.is_file(), "Нет обычного " + имя)
        _требовать(путь.read_bytes() == (ожидаемое + "\n").encode(), "Изменился " + имя)
    for имя in ("CHERRY_PICK_HEAD", "REVERT_HEAD", "rebase-merge", "rebase-apply",
                "sequencer", "BISECT_LOG", "info/grafts"):
        _требовать(not os.path.lexists(_адрес_гит(корень, имя)),
                  "Несовместимая операция Git: " + имя)


def _индекс_и_файлы(корень, ожидаемые):
    путь = _адрес_гит(корень, "index")
    _требовать(not путь.is_symlink() and путь.is_file(), "Необычный файл индекса")
    до = hashlib.sha256(путь.read_bytes()).hexdigest()
    флаги = _гит(корень, "ls-files", "-v", "-z").split(b"\0")
    _требовать(all(not строка or строка.startswith(b"H ") for строка in флаги),
              "Неподдержанные флаги индекса скрывают рабочие файлы")
    записи = _гит(корень, "ls-files", "--stage", "-z").split(b"\0")
    состав = []
    for запись in записи:
        if not запись:
            continue
        поля, имя = запись.split(b"\t", 1)
        режим, объект, стадия = поля.split()
        _требовать(стадия == b"0", "Не разрешены конфликтные стадии индекса")
        состав.append((имя, режим, объект))
    _требовать(состав == ожидаемые, "Подготовленный индекс отличается от дерева кандидата")
    _без_внешних_фильтров(корень)
    _требовать(_гит(корень, "diff-files", "--raw", "-z", "--no-ext-diff", "--no-textconv",
                       "--ignore-submodules=none", "--") == b"",
              "Изменились рабочие файлы относительно индекса")
    _требовать(_гит(корень, "ls-files", "--others", "--exclude-standard", "-z") == b"",
              "Рабочее дерево содержит неотслеживаемые файлы")
    _требовать(hashlib.sha256(путь.read_bytes()).hexdigest() == до,
              "Индекс изменился во время чтения")
    return до


def проверить_готовое_слияние(корень, получатель, источник):
    """Точное stage0 и чистота Git в кооперативном дереве с одним писателем.

    Успех не доказывает исход команды merge, подлинность ревью и право
    продолжения частичной операции. Игнорируемые файлы не входят в результат.
    """
    корень = Path(корень)
    _требовать(корень.is_absolute() and корень.resolve(strict=True) == корень,
              "Нужен физический абсолютный корень")
    _ветка(получатель, "получатель")
    _ветка(источник, "источник")
    _требовать(получатель["ветка"] != источник["ветка"]
              and получатель["коммит"] != источник["коммит"], "Нужны разные ветки и коммиты")
    _требовать(получатель["ветка"] != "refs/heads/master", "Специальный маршрут master не поддержан")
    _требовать(_текст(корень, "rev-parse", "--show-toplevel") == str(корень), "Чужой корень Git")
    _основания(корень, получатель, источник)
    try:
        _гит(корень, "merge-base", "--is-ancestor", получатель["коммит"], источник["коммит"])
    except ValueError as ошибка:
        raise ValueError("Основа не подтверждена предком кандидата") from ошибка
    ожидаемые = []
    for запись in _гит(корень, "ls-tree", "-r", "-z", "--full-tree", источник["коммит"]).split(b"\0"):
        if запись:
            поля, имя = запись.split(b"\t", 1)
            режим, _, объект = поля.split()
            ожидаемые.append((имя, режим, объект))
    ожидаемые.sort()
    индекс = _индекс_и_файлы(корень, ожидаемые)
    _основания(корень, получатель, источник)
    _требовать(_индекс_и_файлы(корень, ожидаемые) == индекс, "Изменился индекс слияния")
    _основания(корень, получатель, источник)
    return {"схема": "fum.фаза-обратного-приёма.1", "дерево": источник["дерево"],
            "родители": [получатель["коммит"], источник["коммит"]],
            "индекс_sha256": индекс, "разрешение_записи": False}

def дочерний_режим(параметры):
    return (параметры.get('схема'), параметры.get('режим')) in {
        ('fum.создание-коммита.3', 'дочерняя-передача'), ('fum.создание-коммита.4', 'дочерний-приём')}


def приём_режим(параметры):
    return параметры.get('схема') == 'fum.создание-коммита.4' and параметры.get('режим') == 'дочерний-приём'


def базисная_точка(параметры):
    return type(параметры) is dict and параметры.get("схема") == "fum.создание-коммита.12"



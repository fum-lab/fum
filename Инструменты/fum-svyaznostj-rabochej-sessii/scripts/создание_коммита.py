def измерить(профиль, название, действие, *аргументы, **параметры):
    начало = time.perf_counter_ns()
    исход = "отказ"
    try:
        результат = действие(*аргументы, **параметры)
        исход = "успех"
        return результат
    finally:
        профиль.append({"стадия": название, "длительность_наносекунды": time.perf_counter_ns() - начало, "исход": исход})


def путь(значение, *, приватный=False):
    результат = Path(значение)
    требовать(результат.is_absolute() and результат == результат.resolve(), "нужен абсолютный физический путь без символических ссылок")
    if приватный:
        требовать(not any(os.path.lexists(предок / ".git") for предок in результат.parents), "приватный файл должен быть вне Git")
    return результат


def прочитать(значение, *, приватный=False):
    файл = путь(значение, приватный=приватный)
    with os.fdopen(os.open(файл, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
        требовать(stat.S_ISREG(os.fstat(поток.fileno()).st_mode), "требуется обычный файл")
        return поток.read()


ПРЕДЕЛ_ГИТА = 120


def гит(корень, *аргументы, среда=None, исполнитель_гита=None, параметры_гита=()):
    процесс = None
    старые_обработчики = {}
    отложенные = []
    def принять_сигнал(номер, кадр):
        # Обработчик не бросает даже при повторном сигнале во время очистки.
        отложенные.append(номер)
    исход = {"код": None, "тайм_аут": False, "исполнение_завершено": False, "прерывание": None}
    try:
        for номер in (signal.SIGINT, signal.SIGTERM):
            старые_обработчики[номер] = signal.signal(номер, принять_сигнал)
        процесс = subprocess.Popen([исполнитель_гита or "git", "--no-replace-objects", *параметры_гита, "-C", str(корень), *аргументы],
            env=среда, stdout=subprocess.PIPE, stderr=subprocess.PIPE, start_new_session=True)
        предел = time.monotonic() + ПРЕДЕЛ_ГИТА
        while True:
            if отложенные:
                прервать(отложенные[0], None)
            осталось = предел - time.monotonic()
            if осталось <= 0:
                raise subprocess.TimeoutExpired(процесс.args, ПРЕДЕЛ_ГИТА)
            try:
                вывод, _ = процесс.communicate(timeout=min(0.1, осталось))
                break
            except subprocess.TimeoutExpired:
                pass
        if отложенные:
            прервать(отложенные[0], None)
        исход.update(код=процесс.returncode, исполнение_завершено=True)
        if процесс.returncode != 0:
            raise subprocess.SubprocessError("операция Git отказала")
        return вывод
    except BaseException as причина:
        исход["тайм_аут"] = isinstance(причина, subprocess.TimeoutExpired)
        if isinstance(причина, (KeyboardInterrupt, ПрерываниеОперации)):
            исход["прерывание"] = str(причина) if isinstance(причина, ПрерываниеОперации) else "KeyboardInterrupt"
        if процесс is not None:
            # Любой выход по исключению останавливает собственную группу,
            # даже если родитель Git успел завершиться раньше потомка hook.
            заблокированные = signal.pthread_sigmask(signal.SIG_BLOCK, {signal.SIGINT, signal.SIGTERM})
            try:
                try:
                    os.killpg(процесс.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
                процесс.communicate(timeout=5)
                исход.update(код=процесс.returncode, исполнение_завершено=True)
            except (OSError, subprocess.SubprocessError):
                исход["исполнение_завершено"] = False
            finally:
                for поток in (процесс.stdout, процесс.stderr):
                    if поток is not None:
                        поток.close()
                signal.pthread_sigmask(signal.SIG_SETMASK, заблокированные)
        if отложенные and исход["прерывание"] is None:
            исход["прерывание"] = signal.Signals(отложенные[0]).name
        ошибка = ОшибкаКоммита("операция Git не завершилась успешно: " + аргументы[0])
        ошибка.процесс = исход
        raise ошибка from причина
    finally:
        for номер, прежний in старые_обработчики.items():
            signal.signal(номер, прежний)


def явные_даты():
    return {ключ: os.environ[ключ] for ключ in ("GIT_AUTHOR_DATE", "GIT_COMMITTER_DATE") if ключ in os.environ}


def идентичность(корень, вид, среда=None, *, читать_гит=None):
    значение = (читать_гит or гит)(корень, "var", вид, среда=среда).decode().rstrip("\n")
    совпадение = re.fullmatch(r"([^\n<>]+) <([^\n<>]+)> (-?\d+) ([+-]\d{4})", значение)
    требовать(совпадение is not None, "неполная идентичность Git")
    return list(совпадение.groups())


def адрес_дерева(параметры, *, читать_гит=None):
    читать_гит = читать_гит or гит
    требовать(os.environ.get("CODEX_THREAD_ID") == исполнитель(параметры), "отсутствующий или чужой native UUID процесса")
    # Читающая политика конфигурации и наблюдаемые identity сохраняются.
    # Перенаправление репозитория, индекса или объектов недопустимо.
    запрещённые = {"GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR",
        "GIT_OBJECT_DIRECTORY", "GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_CONFIG_PARAMETERS", "GIT_CONFIG_COUNT",
        "GIT_REPLACE_REF_BASE", "GIT_SHALLOW_FILE", "GIT_NAMESPACE"}
    требовать(not запрещённые.intersection(os.environ), "перенаправляющая среда Git запрещена")
    корень = путь(параметры["корень"])
    требовать(читать_гит(корень, "rev-parse", "--show-toplevel").decode().strip() == str(корень), "нужен точный корень Git")
    ветка = параметры["ветка"]
    if параметры.get('схема') == 'fum.создание-коммита.8' or повторная_точка(параметры):
        import обычное_поручение
        if повторная_точка(параметры):
            import полномочия_повторного_состояния_узла as полномочия
        else:
            import полномочия_ветки_состояния_узла as полномочия
        акт = обычное_поручение.прочитать_акт(корень, параметры['выбранное_поручение'], новый_эффект=False)
        полномочия.проверить_дерево(корень, исполнитель(параметры), ветка, акт['полномочия_узла'],
            исходный_коммит=параметры['исходный_коммит'], цели=параметры['разрешённые_цели'], новый_эффект=False)
    else:
        требовать(ветка in ("refs/heads/fuma", "refs/heads/planirovaniye") or ветка.startswith("refs/heads/codex/"), "контрольная точка разрешена только в собственной рабочей ветке")
    требовать(ветка.startswith("refs/heads/") and читать_гит(корень, "symbolic-ref", "HEAD").decode().strip() == ветка, "не совпадает полный ref")
    деревья = читать_гит(корень, "worktree", "list", "--porcelain").decode().split("\n\n")
    владельцы = [блок for блок in деревья if "branch " + ветка in блок.splitlines()]
    требовать(len(владельцы) == 1 and владельцы[0].splitlines()[0] == "worktree " + str(корень), "ветка принадлежит другому или нескольким деревьям")
    return корень


def адрес(параметры, *, читать_гит=None):
    читать_гит = читать_гит or гит
    корень = адрес_дерева(параметры, читать_гит=читать_гит)
    голова = читать_гит(корень, "rev-parse", "--verify", "HEAD").decode().strip()
    требовать(голова == параметры["исходный_коммит"] and re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", голова), "не совпадает полный HEAD")
    родители = параметры["родители"]
    требовать(isinstance(родители, list) and len(родители) in (1, 2) and родители[0] == голова and len(set(родители)) == len(родители), "неверные ожидаемые родители")
    каталог_гита = Path(читать_гит(корень, "rev-parse", "--absolute-git-dir").decode().strip())
    слияние = каталог_гита / "MERGE_HEAD"
    фактические = [голова] + (прочитать(слияние).decode().splitlines() if слияние.exists() else [])
    требовать(родители == фактические, "состояние слияния не совпадает с ожидаемыми родителями")
    for имя in ("CHERRY_PICK_HEAD", "REVERT_HEAD", "rebase-merge", "rebase-apply", "sequencer"):
        требовать(not os.path.lexists(каталог_гита / имя), "незавершённая неподдержанная операция Git")
    требовать(str(uuid.UUID(параметры["задача"])) == параметры["задача"], "неканонический корневой UUID")
    требовать(проверить_роль(параметры["имя_автора"]), "неверный формат роли автора")
    return корень


def команды(параметры):
    if дочерний_режим(параметры):
        return сверить_тексты(параметры, передача(параметры).первичные(параметры))
    результат = []
    требовать(isinstance(параметры["источники"], list) and параметры["источники"], "нужны первичные источники команд")
    for источник in параметры["источники"]:
        поля = {"путь", "задача", "экземпляры"}
        ограниченный = повторная_точка(параметры) or параметры.get('схема') in {'fum.создание-коммита.5', 'fum.создание-коммита.6', 'fum.создание-коммита.7', 'fum.создание-коммита.8', 'fum.создание-коммита.9', 'fum.создание-коммита.10'}
        if ограниченный:
            требовать(параметры.get('режим') == 'контрольная-точка', 'выбор разрешён только контрольной точке')
            поля |= {'граница_снимка'}
        требовать(set(источник) in (поля, поля | {"кэш"}), "неверные поля первичного источника")
        if "кэш" in источник:
            требовать(isinstance(источник["кэш"], str) and источник["кэш"], "нужен точный путь приватного кэша команд")
        снимок = сообщения.прочитать_сообщения(источник["путь"], источник["задача"],
            корень_репозитория=параметры["корень"], кэш=источник.get("кэш"), без_записи=True)
        if ограниченный:
            выбор_команд.проверить_снимок(снимок, источник['граница_снимка'], требовать)
        else:
            требовать(снимок["полнота_подтверждена"] and not снимок["дописано_после_снимка"], "нет полного первичного источника команд; нужна отдельная сверка")
        выбранные = источник["экземпляры"]
        требовать(isinstance(выбранные, list) and выбранные and len(set(выбранные)) == len(выбранные), "нужны неповторяющиеся идентичности реальных экземпляров")
        выбор = [элемент for элемент in снимок["сообщения"] if элемент["экземпляр"] in выбранные]
        требовать([элемент["экземпляр"] for элемент in выбор] == выбранные, "первичные экземпляры отсутствуют или нарушен их порядок")
        for элемент in выбор:
            содержимое = элемент["содержимое"]
            требовать(элемент["происхождение"] == "человек", "неподдержанный или неоднозначный первичный ввод")
            if повторная_точка(параметры) or параметры.get('схема') in {'fum.создание-коммита.6', 'fum.создание-коммита.7', 'fum.создание-коммита.8', 'fum.создание-коммита.10'}:
                текст = извлечь_текст(содержимое, требовать)
            else:
                требовать(len(содержимое) == 1 and содержимое[0]["type"] == "input_text", "неподдержанный или неоднозначный первичный ввод")
                текст = содержимое[0]['text']
            результат.append({"задача": источник["задача"], "экземпляр": элемент["экземпляр"],
                "позиция": элемент["позиция"], "текст": текст})
    ключи = [(элемент["задача"], элемент["экземпляр"]) for элемент in результат]
    требовать(len(set(ключи)) == len(ключи), "экземпляр повторён в разных выборах")
    return сверить_тексты(параметры, результат)


def сверить_тексты(параметры, результат):
    if повторная_точка(параметры):
        import журнал_повторного_состояния_узла as журнал
        return журнал.проверить_команды(параметры, результат)
    запрос = прочитать(Path(параметры["корень"]) / параметры["запрос"]).decode()
    раздел = связность.section_body(запрос, "Текст запроса")
    требовать(раздел is not None, "нет дословного раздела запроса")
    образец = re.compile(r"^(?:<!-- FUM-INTAKE: (?P<метка>[0-9a-f]{64}) -->\n\n)?(?P<ограда>`{3,}|~{3,})text[ \t]*\n(?P<текст>.*?)^(?P=ограда)[ \t]*$", re.M | re.S)
    найденные = list(образец.finditer(раздел))
    требовать(not образец.sub("", раздел).strip(), "раздел запроса требует явные отдельные текстовые блоки")
    требовать([элемент.group("текст") for элемент in найденные] == [элемент["текст"] + "\n" for элемент in результат],
        "дословные команды запроса не совпадают с выбранными первичными экземплярами")
    требовать(all(блок.group("метка") in (None, оригинал["экземпляр"]) for блок, оригинал in zip(найденные, результат, strict=True)),
        "метка приёма не совпадает с первичным экземпляром")
    return результат



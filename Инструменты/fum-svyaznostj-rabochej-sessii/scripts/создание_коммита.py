def подготовить(параметры, *, сохранить_историю=False, доверенное_поручение=None, выбранный_состав=None):
    """Подготовить источники и сообщение ДО staging и адресных проверок."""
    if базисная_точка(параметры):
        требовать(not сохранить_историю and выбранный_состав is None, "B не принимает старые адаптеры")
        return вызов_базиса("подготовить_базис", параметры, доверенное_поручение, sys.modules[__name__])
    начало = time.perf_counter_ns()
    try:
        поля = ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ
        дочерняя = дочерний_режим(параметры)
        требовать(параметры.get('режим') == 'контрольная-точка' or дочерняя,
            'итоговый режим пока не подключён')
        добавочные = {'исполнитель', 'назначение_sha256'} | ({'основание_sha256', 'приём'} if приём_режим(параметры) else set())
        требовать((дочерняя and set(параметры) == поля | добавочные)
            or (обычная_точка(параметры) and set(параметры) == поля | {'исполнитель', 'выбранное_поручение'} |
                ({'контракт_журнала'} if независимая_точка(параметры) else
                    {'повторный_журнал'} if повторная_точка(параметры) else set()))
            or (параметры.get('схема') == 'fum.создание-коммита.9' and set(параметры) == поля | {'контракт_журнала'})
            or (set(параметры) == поля and параметры['схема'] in {'fum.создание-коммита.2', 'fum.создание-коммита.5', 'fum.создание-коммита.6'}
                and параметры['режим'] == 'контрольная-точка'), 'неверный контракт подготовки')
        проверить_свежего_автора(параметры)
        привязка = сверить_обычное_поручение(параметры, доверенное_поручение)
        корень = адрес(параметры)
        разрешённые_цели(корень, параметры)
        if дочерняя:
            передача(параметры).проверить(параметры)
        _, _, _, каталог, сессия = отчёты.разрешить_сессию(корень, параметры["запрос"])
        записи = отчёты.прочитать_историю_проверок(каталог, сессия) if os.path.lexists(каталог) else []
        требовать(not записи or отчёты.есть_раунды(записи), "подготовка требует историю проверок v4; существующая v3 не преобразуется автоматически")
        пути = [путь(параметры[ключ], приватный=True) for ключ in ("сообщение", "подготовка", "квитанция")]
        требовать(len(set(пути)) == len(пути) and not any(os.path.lexists(файл) for файл in пути), "нужны новые различные приватные файлы")
        первичные = команды(параметры)
        журнал = сверить_независимый_журнал(параметры, выбранный_состав, доверенное_поручение=доверенное_поручение)
        повтор = сверить_повторный_журнал(параметры, доверенное_поручение)
        готовность.проверить_постановку(параметры_готовности(параметры, привязка, журнал, повтор), первичные)
        автор = идентичность(корень, "GIT_AUTHOR_IDENT")
        коммиттер = идентичность(корень, "GIT_COMMITTER_IDENT")
        требовать(isinstance(параметры["заголовок"], str) and параметры["заголовок"].strip() and "\n" not in параметры["заголовок"], "нужен однострочный заголовок")
        требовать(isinstance(параметры["описание"], str) and параметры["описание"].strip(), "нужно описание сделанного")
        метка = ('Адресное поручение приёма корня:' if приём_режим(параметры) else
            'Первоначальное поручение корня:' if дочерняя else 'Исходные пользовательские команды:')
        основа = параметры["заголовок"] + "\n\n" + параметры["описание"] + '\n\n' + метка + '\n\n'
        основа += "\n\n".join(элемент["текст"] for элемент in первичные)
        основа += "\n\nCodex-Thread-ID: " + параметры["задача"] + "\n"
        путь_запроса = корень / параметры['запрос']
        if повторная_точка(параметры):
            import журнал_повторного_состояния_узла as повторный_журнал
            повторный_журнал.проверить_корневую_метку(параметры, связность)
        else:
            требовать(not связность.validate_codex_thread_id_section(
                прочитать(путь_запроса).decode(), путь_запроса, параметры['задача']), 'неверный последний корневой trailer')
        # Подготовитель сохраняет исходное тело и отвергает лишний trailer.
        сверка = None
        требовать(сверить_обычное_поручение(параметры, доверенное_поручение) == привязка,
            'поручение изменилось перед наблюдением модели')
        требовать(сверить_независимый_журнал(параметры, выбранный_состав, доверенное_поручение=доверенное_поручение) == журнал,
            'независимый Журнал изменился перед наблюдением модели')
        if сохранить_историю:
            from повторная_подготовка_модели import наблюдать_сохранённую
            модель, сверка, сохранённые_байты = наблюдать_сохранённую(параметры, прочитать, наблюдать_модель)
        else:
            модель = наблюдать_модель(параметры, без_записи=False)
        имя_автора = составить_имя(параметры["имя_автора"], модель["последнее"])
        сообщение = модели.подготовить_коммит(основа, модель, параметры["задача"])
        путь_запроса = корень / параметры["запрос"]
        if повторная_точка(параметры):
            повторный_журнал.проверить_корневую_метку(параметры, связность, сообщение)
        else:
            требовать(not связность.validate_commit_message_codex_thread_id(прочитать(путь_запроса).decode(), путь_запроса, сообщение), "неверный последний корневой trailer")
        if сохранить_историю:
            требовать(прочитать(корень / параметры['история_модели']) == сохранённые_байты,
                'история изменилась перед сохранением подготовки')
        требовать(сверить_независимый_журнал(параметры, выбранный_состав, доверенное_поручение=доверенное_поручение) == журнал,
            'независимый Журнал изменился перед сохранением сообщения')
        модели.сохранить_сообщение(пути[0], сообщение)
        подготовка = {"схема": версия_подготовки(параметры), "параметры": параметры, "имя_автора": имя_автора,
            "готовность": str(готовность.путь_этапа(параметры)),
            "команды": первичные, "модель": модель["последнее"], "наблюдений": модель["число_наблюдений"],
            "история_sha256": модель["история_sha256"], "сообщение_sha256": хэш(сообщение.encode()),
            "исходный_автор": автор, "исходный_коммиттер": коммиттер, "явные_даты": явные_даты()}
        if привязка is not None:
            подготовка['привязка_поручения'] = привязка
        if журнал is not None:
            подготовка['привязка_журнала'] = журнал
        if повтор is not None:
            требовать(сверить_повторный_журнал(параметры, доверенное_поручение) == повтор,
                'повторная цепь изменилась перед сохранением подготовки')
            подготовка['привязка_повтора'] = повтор
        требовать(сверить_независимый_журнал(параметры, выбранный_состав, доверенное_поручение=доверенное_поручение) == журнал,
            'независимый Журнал изменился перед сохранением подготовки')
        модели.сохранить_сообщение(пути[1], байты(подготовка).decode())
        результат = {"схема": "fum.результат-подготовки-коммита.1", "подготовка": str(пути[1]), "сообщение_sha256": подготовка["сообщение_sha256"], "коммит_создан": False}
        if сверка is not None:
            результат['сверка_истории'] = сверка
        return результат
    except (OSError, ValueError, KeyError, TypeError, KeyboardInterrupt, ПрерываниеОперации, отчёты.ОшибкаОтчёта) as причина:
        ошибка = ОшибкаКоммита(str(причина))
        ошибка.длительность_наносекунды = time.perf_counter_ns() - начало
        ошибка.профиль = [{"стадия": "подготовка сообщения", "исход": "отказ", "длительность_наносекунды": ошибка.длительность_наносекунды}]
        raise ошибка from причина


def индекс(корень):
    """Сверить ВСЕ stage-0 байты и режимы, включая исключения отпечатка отчёта."""
    исходное = гит(корень, "ls-files", "--stage", "-v", "-z")
    алгоритм = гит(корень, "rev-parse", "--show-object-format").decode().strip()
    требовать(алгоритм in ("sha1", "sha256"), "неподдержанный формат объектов")
    требовать(not гит(корень, "ls-files", "--others", "--exclude-standard", "-z"), "неиндексированный хвост")
    for строка in исходное.split(b"\0"):
        if not строка:
            continue
        сведения, имя = строка.split(b"\t", 1)
        флаг, режим, объект, стадия = сведения.decode().split()
        требовать(флаг == "H" and стадия == "0", "конфликт, skip-worktree или assume-unchanged в индексе")
        файл = корень / os.fsdecode(имя)
        требовать(файл.parent == файл.parent.resolve(), "символическая ссылка в родителе индексного пути")
        состояние = файл.lstat()
        if режим == "160000":
            требовать(stat.S_ISDIR(состояние.st_mode), "неподдержанное состояние gitlink")
            требовать(гит(файл, "rev-parse", "HEAD").strip() == объект.encode(), "gitlink не совпадает с индексом")
            continue
        if режим == "120000":
            требовать(stat.S_ISLNK(состояние.st_mode), "режим ссылки не совпадает с индексом")
            данные = os.fsencode(os.readlink(файл))
            вычисленный = hashlib.new(алгоритм, b"blob " + str(len(данные)).encode() + b"\0" + данные).hexdigest()
        else:
            требовать(режим in ("100644", "100755") and stat.S_ISREG(состояние.st_mode), "неподдержанный режим индексного файла")
            требовать(bool(состояние.st_mode & stat.S_IXUSR) == (режим == "100755"), "режим файла не совпадает с индексом")
            вычисление = hashlib.new(алгоритм, b"blob " + str(состояние.st_size).encode() + b"\0")
            with файл.open("rb") as поток:
                for часть in iter(lambda: поток.read(1024 * 1024), b""):
                    вычисление.update(часть)
            вычисленный = вычисление.hexdigest()
        требовать(вычисленный == объект, "байты файла не совпадают с индексом: " + os.fsdecode(имя))
    требовать(исходное == гит(корень, "ls-files", "--stage", "-v", "-z"), "индекс изменился при чтении")
    return хэш(исходное)


def проверки(корень, параметры, необходимые):
    требовать(isinstance(необходимые, list) and необходимые and len(set(необходимые)) == len(необходимые), "нужен явный непустой перечень обязательных UUID проверок")
    _, _, отчёт, каталог, сессия = отчёты.разрешить_сессию(корень, параметры["запрос"])
    отчёты.запретить_действие_при_возобновлении(каталог, "создание коммита")
    записи = отчёты.прочитать_историю_проверок(каталог, сессия)
    if приём_режим(параметры):
        передача(параметры).проверки(параметры, необходимые, записи)
    требовать(отчёты.есть_раунды(записи), "создание требует историю проверок v4")
    требовать(all(запись["состояние"] == "завершён" for _, запись, _ in записи), "есть активные проверки")
    текущий, содержимое = отчёты.текущий_контекст_проверок(корень, сессия, записи)
    по_номерам = {запись["идентификатор"]: запись for _, запись, _ in записи}
    for номер in необходимые:
        запись = по_номерам.get(номер)
        требовать(запись is not None and запись["схема"] == "fum.test-run.v4" and запись["статус"] == "успешно" and запись["код_завершения"] == 0,
            "обязательная проверка отсутствует или неуспешна: " + str(номер))
        требовать(запись["профиль_проверки"]["отпечаток_снимка"] == текущий and запись["отпечаток_содержимого"] == содержимое,
            "обязательная проверка относится к другому входу: " + номер)
    требовать(параметры["режим"] == "контрольная-точка" or дочерний_режим(параметры), "итоговый режим пока не подключён")
    ошибки = отчёты.проверить_журнал_сессии(корень, параметры["запрос"], контрольная_точка=True)
    требовать(not ошибки, "; ".join(ошибки))
    return {"гит": текущий, "содержимое": содержимое, "история": хэш(b"".join(сырые for _, _, сырые in записи)),
        "свидетельства": [[запись["идентификатор"], хэш(сырые)] for _, запись, сырые in записи]}


def проверить_объект(корень, ожидаемое, объект, *, читать_гит=None):
    читать_гит = читать_гит or гит
    сырой = читать_гит(корень, "cat-file", "commit", объект)
    алгоритм = читать_гит(корень, "rev-parse", "--show-object-format").decode().strip()
    требовать(hashlib.new(алгоритм, b"commit " + str(len(сырой)).encode() + b"\0" + сырой).hexdigest() == объект, "OID не совпадает с сырым объектом")
    заголовки, сообщение = сырой.split(b"\n\n", 1)
    поля = {}
    for строка in заголовки.splitlines():
        if строка.startswith(b" "):
            continue
        ключ, значение = строка.split(b" ", 1)
        поля.setdefault(ключ.decode(), []).append(значение.decode())
    требовать(поля.get("tree") == [ожидаемое["дерево"]] and поля.get("parent") == ожидаемое["родители"], "дерево или родители созданного коммита не совпадают")
    требовать(хэш(сообщение) == ожидаемое["сообщение_sha256"], "сообщение созданного коммита не совпадает")
    for ключ, цель in (("author", ожидаемое["автор"]), ("committer", ожидаемое["коммиттер"])):
        значения = поля.get(ключ, [])
        требовать(len(значения) == 1, "неоднозначное поле " + ключ)
        совпадение = re.fullmatch(r"([^\n<>]+) <([^\n<>]+)> (-?\d+) ([+-]\d{4})", значения[0])
        требовать(совпадение is not None and list(совпадение.groups())[:2] == цель[:2], "фактическая идентичность не совпадает: " + ключ)
        if ожидаемое["явные_даты"].get("GIT_" + ключ.upper() + "_DATE") is not None:
            требовать(list(совпадение.groups())[2:] == цель[2:], "явная дата созданного коммита не совпадает: " + ключ)
    return {"коммит": объект, "дерево": поля["tree"][0], "родители": поля["parent"],
        "автор": поля["author"][0], "коммиттер": поля["committer"][0], "сообщение_sha256": хэш(сообщение)}


def сверить_ожидание_квитанции(квитанция, подготовка, параметры):
    """Проверить сохранённый контракт по подготовке без текущих identity и модели."""
    ожидание = квитанция.get("ожидание")
    требовать(type(ожидание) is dict and set(ожидание) == {
        "ветка", "исходный_коммит", "родители", "дерево", "сообщение_sha256", "автор", "коммиттер", "явные_даты"},
        "неполный формат ожидания квитанции")
    даты = ожидание["явные_даты"]
    требовать(type(даты) is dict and set(даты) <= {"GIT_AUTHOR_DATE", "GIT_COMMITTER_DATE"}
        and all(type(значение) is str and значение for значение in даты.values()), "неверный формат явных дат квитанции")
    for ключ in ("ветка", "исходный_коммит", "родители"):
        требовать(ожидание[ключ] == параметры[ключ], "ожидание расходится с подготовкой: " + ключ)
    for ключ in ("сообщение_sha256", "явные_даты"):
        требовать(ожидание[ключ] == подготовка[ключ], "ожидание расходится с подготовкой: " + ключ)
    for ключ, исходный in (("автор", "исходный_автор"), ("коммиттер", "исходный_коммиттер")):
        значение = ожидание[ключ]
        требовать(type(значение) is list and len(значение) == 4
            and all(type(элемент) is str and элемент for элемент in значение)
            and re.fullmatch(r"-?\d+", значение[2]) is not None
            and re.fullmatch(r"[+-]\d{4}", значение[3]) is not None, "неполная identity ожидания: " + ключ)
        оригинал = подготовка[исходный]
        требовать(значение[1] == оригинал[1]
            and (ключ != "коммиттер" or значение[:2] == оригинал[:2]), "identity расходится с подготовкой: " + ключ)
        поле_даты = "GIT_AUTHOR_DATE" if ключ == "автор" else "GIT_COMMITTER_DATE"
        требовать(поле_даты not in даты or значение[2:] == оригинал[2:], "явная дата расходится с подготовкой: " + ключ)
    требовать("имя_автора" not in подготовка or ожидание["автор"][0] == подготовка["имя_автора"],
        "сохранённое имя автора расходится с подготовкой")
    имя = ожидание["автор"][0]
    требовать(проверить_формат(имя), "неверный формат сохранённого имени автора")
    полное = ПОЛНОЕ_ИМЯ.fullmatch(имя)
    требовать((полное[1] if полное is not None else имя) == параметры["имя_автора"],
        "сохранённая роль автора расходится с подготовкой")


def восстановить(корень, квитанция, путь_квитанции, *, читать_гит=None):
    """Только чтение готовой квитанции; её исходные байты не устанавливаются."""
    читать_гит = читать_гит or гит
    требовать(type(квитанция) is dict and квитанция.get("схема") == "fum.квитанция-создания-коммита.1"
        and квитанция.get("состояние") == "проверен", "нужна успешная завершённая квитанция; повтор запрещён")
    процесс = квитанция.get("процесс")
    требовать(type(процесс) is dict and set(процесс) == {"код", "тайм_аут", "исполнение_завершено", "прерывание"}
        and type(процесс["код"]) is int and процесс["код"] == 0
        and процесс["исполнение_завершено"] is True and процесс["тайм_аут"] is False
        and процесс["прерывание"] is None, "квитанция не подтверждает успешное завершение процесса; повтор запрещён")
    сохранённый = квитанция.get("результат")
    требовать(type(сохранённый) is dict and set(сохранённый) == {"коммит", "дерево", "родители", "автор", "коммиттер", "сообщение_sha256"},
        "неполный или неизвестный формат сохранённого результата")
    объект = сохранённый["коммит"]
    требовать(type(объект) is str and re.fullmatch(r"(?:[0-9a-f]{40}|[0-9a-f]{64})", объект) is not None,
        "нужен полный точный OID сохранённой квитанции")
    требовать(квитанция.get("наблюдённый_коммит") == объект,
        "наблюдённый OID расходится с сохранённым результатом")
    ожидаемое = квитанция["ожидание"]
    требовать(объект != ожидаемое["исходный_коммит"], "квитанция не подтверждает новый коммит")
    требовать(читать_гит(корень, "symbolic-ref", "HEAD").decode().strip() == ожидаемое["ветка"], "ref после попытки изменён; повтор запрещён")
    требовать(читать_гит(корень, "rev-parse", "HEAD").decode().strip() == объект, "HEAD не совпадает с сохранённым OID; повтор запрещён")
    итог = проверить_объект(корень, ожидаемое, объект, читать_гит=читать_гит)
    требовать(итог == сохранённый, "сырой объект расходится с полным сохранённым результатом")
    требовать(читать_гит(корень, "symbolic-ref", "HEAD").decode().strip() == ожидаемое["ветка"]
        and читать_гит(корень, "rev-parse", "HEAD").decode().strip() == объект, "ref или HEAD изменились во время сверки квитанции")
    return итог


def _зафиксировать_новую_квитанцию(корень, квитанция, путь_квитанции, *, обычные_параметры=None):
    """Первичная фиксация только после собственного нового Git-вызова."""
    ожидаемое = квитанция["ожидание"]
    голова = гит(корень, "rev-parse", "HEAD").decode().strip()
    требовать(гит(корень, "symbolic-ref", "HEAD").decode().strip() == ожидаемое["ветка"], "ref после попытки изменён; повтор запрещён")
    if квитанция.get("процесс", {}).get("исполнение_завершено") is not True:
        квитанция.update(состояние="исход-процесса-неизвестен", наблюдённый_коммит=голова)
        сообщения._установить(путь_квитанции, байты(квитанция))
        raise ОшибкаКоммита("неполная квитанция не подтверждает завершение процесса; автоматический повтор запрещён")
    if голова == ожидаемое["исходный_коммит"]:
        квитанция.update(состояние="коммит-не-наблюдается", наблюдённый_коммит=голова)
        сообщения._установить(путь_квитанции, байты(квитанция))
        raise ОшибкаКоммита("после попытки новый коммит не наблюдается; автоматический повтор запрещён")
    try:
        итог = проверить_объект(корень, ожидаемое, голова)
        if обычные_параметры is not None:
            публикационный_адаптер().последний_адрес(обычные_параметры, sys.modules[__name__], ожидаемый=голова)
    except ОшибкаКоммита:
        квитанция.update(состояние="расхождение-после-создания", наблюдённый_коммит=голова)
        сообщения._установить(путь_квитанции, байты(квитанция))
        raise
    if квитанция.get("процесс", {}).get("код") != 0 or квитанция.get("процесс", {}).get("тайм_аут") or квитанция.get("процесс", {}).get("прерывание"):
        квитанция.update(состояние="объект-проверен-после-отказа", результат=итог, наблюдённый_коммит=голова)
        сообщения._установить(путь_квитанции, байты(квитанция))
        raise ОшибкаКоммита("объект проверен после отказа или неизвестного исхода процесса; автоматический повтор запрещён")
    квитанция.update(состояние="проверен", результат=итог, наблюдённый_коммит=голова)
    сообщения._установить(путь_квитанции, байты(квитанция))
    return итог


def прочитать_подготовку_готовности(файл_подготовки, *, доверенное_поручение=None, выбранный_состав=None, новый_эффект=True):
    подготовка = прочитать_подготовку_для_маршрута(файл_подготовки)
    параметры = подготовка["параметры"]
    требовать(подготовка['схема'] == версия_подготовки(параметры), 'неверная версия подготовки готовности')
    if новый_эффект:
        проверить_свежего_автора(параметры, подготовка)
    привязка = сверить_обычное_поручение(параметры, доверенное_поручение, подготовка, новый_эффект=новый_эффект)
    журнал = сверить_независимый_журнал(параметры, выбранный_состав, подготовка, новый_эффект=новый_эффект, доверенное_поручение=доверенное_поручение)
    повтор = сверить_повторный_журнал(параметры, доверенное_поручение, подготовка, новый_эффект=новый_эффект)
    (адрес_дерева if (обычная_точка(параметры) or независимая_точка(параметры)) and not новый_эффект else адрес)(параметры)
    if дочерний_режим(параметры):
        передача(параметры).проверить(параметры)
    требовать(подготовка["готовность"] == str(готовность.путь_этапа(параметры)), "подменён адрес готовности")
    return подготовка, параметры_готовности(параметры, привязка, журнал, повтор)


def объявить_готовность(файл_подготовки, необходимые, предел, замены=None, *, доверенное_поручение=None, выбранный_состав=None):
    """Проверить связность до готовности; перед Git весь допуск повторяется."""
    сырая_подготовка_маршрута = прочитать_подготовку_для_маршрута(файл_подготовки)
    if базисная_точка(сырая_подготовка_маршрута.get("параметры")):
        требовать(выбранный_состав is None, "B не принимает независимый Журнал")
        return вызов_базиса("готово_базис", файл_подготовки, необходимые, предел, замены,
            доверенное_поручение, sys.modules[__name__])
    try:
        сырая = прочитать_подготовку_для_маршрута(файл_подготовки)
        фасад = None
        if not дочерний_режим(сырая['параметры']):
            import типизированная_контрольная_точка as фасад
            сверить_типизированный_вход(фасад, файл_подготовки, необходимые, сырая)
        подготовка, параметры = прочитать_подготовку_готовности(файл_подготовки,
            доверенное_поручение=доверенное_поручение, выбранный_состав=выбранный_состав)
        требовать(подготовка == сырая, 'подготовка изменилась между ранним и полным чтением')
        требовать(not приём_режим(параметры) or not замены, 'Замена назначенной проверки приёма запрещена')
        корень = Path(параметры["корень"])
        публикационный = публикационный_адаптер() if обычная_точка(параметры) else None
        проверить_ранний_состав(корень, параметры)
        if публикационный is not None:
            ранний = фасад.РаннийДопуск(индекс(корень), проверки(корень, параметры, необходимые))
            публикация = публикационный.построить(параметры, sys.modules[__name__])
            текущий = публикационный.снимок_готовности(
                готовность.снимок(параметры, подготовка['команды'], необходимые, ранний.проверки), публикация)
            файл = готовность.путь_этапа(параметры)
            прежнее = готовность.прочитать(файл, параметры) if os.path.lexists(файл) else None
            готовность.поколения.объявить(параметры['корень'], текущий, ранний.проверки['свидетельства'],
                time.time_ns(), предел, прежнее=прежнее, замены=замены)
        else:
            ранний = (фасад.ранний_допуск(корень, параметры, необходимые, подготовка,
                        объявление=(предел, замены)) if фасад is not None else None)
        первичные = команды(параметры)
        требовать(первичные == подготовка["команды"], "первичные команды изменились")
        сообщение = прочитать(параметры["сообщение"], приватный=True)
        требовать(хэш(сообщение) == подготовка["сообщение_sha256"], "сообщение изменилось после подготовки")
        отпечаток = ранний.индекс if ранний is not None else индекс(корень)
        допуск = ранний.проверки if ранний is not None else проверки(корень, параметры, необходимые)
        if повторная_точка(параметры):
            ошибки = связность_повторной_пары(параметры, сообщение.decode())
        elif дочерний_режим(параметры):
            ошибки = передача(параметры).связность(параметры, сообщение.decode(), связность)
        else:
            ошибки = связность.validate_session(корень, параметры["запрос"],
                expected_codex_thread_id=параметры["задача"], commit_message=сообщение.decode(), контрольная_точка=True,
                **параметры_связности(параметры, выбранный_состав, доверенное_поручение=доверенное_поручение))
        требовать(not ошибки, "; ".join(ошибки))
        требовать(индекс(корень) == отпечаток and проверки(корень, параметры, необходимые) == допуск,
            "вход изменился при объявлении готовности")
        требовать(прочитать(параметры["сообщение"], приватный=True) == сообщение,
            "сообщение изменилось при объявлении готовности")
        адрес(параметры)
        сверить_обычное_поручение(подготовка['параметры'], доверенное_поручение, подготовка)
        сверить_независимый_журнал(подготовка['параметры'], выбранный_состав, подготовка, доверенное_поручение=доверенное_поручение)
        текущий = готовность.снимок(параметры, первичные, необходимые, допуск)
        слой = получить_слой(параметры, доверенное_поручение=доверенное_поручение, выбранный_состав=выбранный_состав) if точка_с_доказательством(параметры) else None
        живое = (lambda: получить_слой(параметры, доверенное_поручение=доверенное_поручение, выбранный_состав=выбранный_состав)) if слой is not None else None
        if публикационный is not None:
            текущий = публикационный.снимок_готовности(текущий, публикация)
            return объявить_публикационную_готовность(публикационный, публикация,
                параметры, текущий, допуск, предел, замены, доказательство=слой, получить_живое=живое)
        return готовность.объявить(параметры, текущий, допуск["свидетельства"], предел, замены,
            доказательство=слой, получить_живое=живое)
    except (OSError, ValueError, KeyError, TypeError, отчёты.ОшибкаОтчёта) as ошибка:
        raise ОшибкаКоммита(str(ошибка)) from ошибка


def отозвать_готовность(файл_подготовки, номер, основание, *, доверенное_поручение=None, выбранный_состав=None):
    подготовка = прочитать_подготовку_для_маршрута(файл_подготовки)
    if базисная_точка(подготовка.get("параметры")):
        return вызов_базиса("отозвать_базис", подготовка, номер, основание, доверенное_поручение, sys.modules[__name__])
    try:
        _, параметры = прочитать_подготовку_готовности(файл_подготовки,
            доверенное_поручение=доверенное_поручение, выбранный_состав=выбранный_состав, новый_эффект=False)
        return готовность.отозвать(параметры, номер, основание)
    except (OSError, ValueError, KeyError, TypeError) as ошибка:
        raise ОшибкаКоммита(str(ошибка)) from ошибка


def _создать_проверенный_коммит(файл_подготовки, необходимые, *, доверенное_поручение=None, выбранный_состав=None):
    """Никакого git commit до всех допусков; после неопределённости только чтение."""
    начало = time.perf_counter_ns()
    профиль = []
    try:
        сырая_подготовка = прочитать(файл_подготовки, приватный=True)
        подготовка = разобрать_подготовку(сырая_подготовка)
        требовать(подготовка["схема"] in {"fum.подготовленный-коммит.1", "fum.подготовленный-коммит.2", "fum.подготовленный-коммит.3", "fum.подготовленный-коммит.4", "fum.подготовленный-коммит.5", "fum.подготовленный-коммит.6", "fum.подготовленный-коммит.7", "fum.подготовленный-коммит.8", "fum.подготовленный-коммит.9", "fum.подготовленный-коммит.10", "fum.подготовленный-коммит.11", "fum.подготовленный-коммит.12", "fum.подготовленный-коммит.13"}, "неверная подготовка")
        исходные_параметры = подготовка['параметры']
        привязка = сверить_обычное_поручение(исходные_параметры, доверенное_поручение, подготовка, новый_эффект=False)
        журнал = измерить(профиль, 'независимый журнал: историческая привязка',
            сверить_независимый_журнал, исходные_параметры, выбранный_состав,
            подготовка, новый_эффект=False, доверенное_поручение=доверенное_поручение)
        повтор = подготовка.get('привязка_повтора') if повторная_точка(исходные_параметры) else None
        параметры = параметры_готовности(исходные_параметры, привязка, журнал, повтор)
        дочерняя = дочерний_режим(параметры)
        требовать(параметры["режим"] == "контрольная-точка" or дочерняя, "итоговый режим пока не подключён")
        корень = адрес_дерева(параметры)
        if приём_режим(параметры):
            # Структура и каноническая квитанция, без нового живого допуска H.
            передача(параметры).адрес(параметры)
        файл_квитанции = путь(параметры["квитанция"], приватный=True)
        сохранённый_слой = None
        номер_сверки_слоя = 0
        def сверить_слой():
            nonlocal номер_сверки_слоя
            if точка_с_доказательством(параметры):
                номер_сверки_слоя += 1
                измерить(профиль, f'активный слой: {номер_сверки_слоя}',
                    готовность.сверить_активный_слой, параметры, сохранённый_слой,
                    lambda: получить_слой(параметры, доверенное_поручение=доверенное_поручение, выбранный_состав=выбранный_состав))
        if точка_с_доказательством(исходные_параметры) and not os.path.lexists(файл_квитанции):
            адрес(параметры)
            сверить_обычное_поручение(исходные_параметры, доверенное_поручение, подготовка)
            измерить(профиль, 'независимый журнал: после адреса',
                сверить_независимый_журнал, исходные_параметры, выбранный_состав, подготовка, доверенное_поручение=доверенное_поручение)
            сохранённый_слой = готовность.активное_доказательство(параметры)
            сверить_слой()
        # Только приватный кооперативный замок этого вызова; не блокировка всех писателей Git.
        with os.fdopen(os.open(str(файл_квитанции) + ".lock", os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600), "r+b") as замок:
            fcntl.flock(замок, fcntl.LOCK_EX)
            if os.path.lexists(файл_квитанции):
                прежняя = сообщения._разобрать(прочитать(файл_квитанции, приватный=True))
                требовать(type(прежняя) is dict, "неверный формат квитанции")
                требовать(прежняя["подготовка_sha256"] == хэш(сырая_подготовка), "квитанция относится к другой подготовке")
                сверить_ожидание_квитанции(прежняя, подготовка, параметры)
                return восстановить(корень, прежняя, файл_квитанции)
            if точка_с_доказательством(параметры) and сохранённый_слой is None:
                сохранённый_слой = готовность.активное_доказательство(параметры)
                сверить_слой()
            требовать((дочерняя and подготовка['схема'] == версия_подготовки(параметры))
                or (обычная_точка(параметры) and подготовка['схема'] == версия_подготовки(параметры))
                or (точка_с_доказательством(параметры) and подготовка['схема'] == версия_подготовки(параметры))
                or (подготовка['схема'] == 'fum.подготовленный-коммит.4'
                    and параметры.get('схема') == 'fum.создание-коммита.2')
                or (подготовка['схема'] == 'fum.подготовленный-коммит.7'
                    and параметры.get('схема') == 'fum.создание-коммита.5')
                or (подготовка['схема'] == 'fum.подготовленный-коммит.8'
                    and параметры.get('схема') == 'fum.создание-коммита.6'), 'нужна новая подготовка с адресом готовности')
            проверить_свежего_автора(параметры, подготовка)
            фасад = None
            if not дочерняя:
                import типизированная_контрольная_точка as фасад
                сверить_типизированный_вход(фасад, файл_подготовки, необходимые, подготовка)
            требовать(подготовка["готовность"] == str(готовность.путь_этапа(параметры)), "подменён адрес готовности")
            адрес(параметры)
            измерить(профиль, 'независимый журнал: перед наличием готовности',
                сверить_независимый_журнал, исходные_параметры, выбранный_состав, подготовка, доверенное_поручение=доверенное_поручение)
            измерить(профиль, "наличие готовности", готовность.проверить_доступность, параметры)
            сообщение = прочитать(параметры["сообщение"], приватный=True)
            требовать(хэш(сообщение) == подготовка["сообщение_sha256"], "сообщение изменилось после подготовки")
            if дочерняя:
                # Состав загруженных модулей входит в оба ранних снимка.
                измерить(профиль, 'загрузка дочернего адаптера', передача, параметры)
            публикационный = публикационный_адаптер() if обычная_точка(параметры) else None
            ранний_снимок = измерить(профиль, "ранний состав", проверить_ранний_состав, корень, параметры)
            ранний = (измерить(профиль, "ранний индекс и v4", фасад.ранний_допуск,
                корень, параметры, необходимые, подготовка) if фасад is not None else None)
            if публикационный is not None:
                публикация = измерить(профиль, 'публикационный допуск', публикационный.построить,
                    параметры, sys.modules[__name__])
            требовать(измерить(профиль, "первичные команды", команды, параметры) == подготовка["команды"], "первичные команды изменились")
            модель = измерить(профиль, "модель", наблюдать_модель, параметры, без_записи=True)
            требовать(модель["последнее"] == подготовка["модель"] and модель["число_наблюдений"] == подготовка["наблюдений"], "модель после подготовки изменилась")
            требовать(хэш(прочитать(корень / параметры["история_модели"])) == подготовка["история_sha256"], "сохранённая история модели изменена")
            имя_автора = составить_имя(параметры["имя_автора"], модель["последнее"])
            требовать(подготовка["имя_автора"] == имя_автора, "подготовленное имя автора не совпадает с ролью, моделью и усилием")
            требовать(явные_даты() == подготовка["явные_даты"], "явные даты изменились после подготовки")
            автор = идентичность(корень, "GIT_AUTHOR_IDENT")
            коммиттер = идентичность(корень, "GIT_COMMITTER_IDENT")
            требовать(автор[1] == подготовка["исходный_автор"][1] and коммиттер[:2] == подготовка["исходный_коммиттер"][:2], "исходные email или committer изменились")
            среда = {**os.environ, "GIT_AUTHOR_NAME": имя_автора}
            назначенный = идентичность(корень, "GIT_AUTHOR_IDENT", среда)
            требовать(назначенный[:2] == [имя_автора, автор[1]] and идентичность(корень, "GIT_COMMITTER_IDENT", среда)[:2] == коммиттер[:2], "имя автора меняет другие поля identity")
            повторный_снимок = измерить(профиль, "повторный ранний состав", проверить_ранний_состав, корень, параметры)
            требовать(повторный_снимок == ранний_снимок, "вход ранней сверки изменился после чтения источников")
            отпечаток_индекса = ранний.индекс if ранний is not None else измерить(профиль, "индекс", индекс, корень)
            допуск = ранний.проверки if ранний is not None else измерить(профиль, "обязательные проверки", проверки, корень, параметры, необходимые)
            if повторная_точка(параметры):
                ошибки = измерить(профиль, 'связность повторной пары', связность_повторной_пары, параметры, сообщение.decode())
            elif дочерняя:
                ошибки = измерить(профиль, 'связность слоя', передача(параметры).связность, параметры, сообщение.decode(), связность)
            else:
                ошибки = измерить(профиль, "связность", связность.validate_session, корень, параметры["запрос"], expected_codex_thread_id=параметры["задача"],
                    commit_message=сообщение.decode(), контрольная_точка=True,
                    **параметры_связности(параметры, выбранный_состав, доверенное_поручение=доверенное_поручение))
            требовать(not ошибки, "; ".join(ошибки))
            адрес(параметры)
            требовать(измерить(профиль, "повторная сверка индекса", индекс, корень) == отпечаток_индекса and проверки(корень, параметры, необходимые) == допуск, "вход изменился после допуска")
            требовать(прочитать(параметры["сообщение"], приватный=True) == сообщение and прочитать(файл_подготовки, приватный=True) == сырая_подготовка, "подготовленные байты изменились")
            текущий = готовность.снимок(параметры, подготовка["команды"], необходимые, допуск)
            if публикационный is not None:
                публикационный.сверить(публикация, параметры, sys.modules[__name__])
                текущий = публикационный.снимок_готовности(текущий, публикация)
                сохранённая = готовность.прочитать(готовность.путь_этапа(параметры), параметры)
                требовать(сохранённая['поколения'][-1]['снимок']['отпечаток_содержимого']
                    == текущий['отпечаток_содержимого'], 'публикационный допуск изменился после ready')
            решение_готовности = измерить(профиль, "готовность этапа", готовность.сверить, параметры, текущий, допуск["свидетельства"],
                доказательство=сохранённый_слой[готовность.ключ_доказательства(параметры)] if сохранённый_слой else None,
                получить_живое=(lambda: получить_слой(параметры, доверенное_поручение=доверенное_поручение, выбранный_состав=выбранный_состав)) if сохранённый_слой else None)
            требовать(решение_готовности["фиксировать_этап"], "готовность не разрешает фиксацию: " + решение_готовности["действие"])
            if дочерняя:
                измерить(профиль, 'повторный допуск назначения', передача(параметры).проверить, параметры)
                требовать(индекс(корень) == отпечаток_индекса
                    and проверки(корень, параметры, необходимые) == допуск, 'вход изменился после допуска назначения')
            if обычная_точка(параметры):
                измерить(профиль, 'последняя сверка обычного поручения', сверить_обычное_поручение,
                    исходные_параметры, доверенное_поручение, подготовка)
                последняя_модель = измерить(профиль, 'последняя сверка модели исполнителя',
                    наблюдать_модель, параметры, без_записи=True)
                требовать(последняя_модель['последнее'] == подготовка['модель']
                    and последняя_модель['число_наблюдений'] == подготовка['наблюдений'],
                    'модель исполнителя изменилась после последнего допуска готовности')
                требовать(хэш(прочитать(корень / параметры['история_модели'])) == подготовка['история_sha256'],
                    'сохранённая история модели изменилась после последнего допуска готовности')
                адрес(параметры)
                требовать(индекс(корень) == отпечаток_индекса and проверки(корень, параметры, необходимые) == допуск
                    and прочитать(параметры['сообщение'], приватный=True) == сообщение
                    and прочитать(файл_подготовки, приватный=True) == сырая_подготовка,
                    'вход изменился после последней сверки поручения')
            if публикационный is not None:
                публикационный.сверить(публикация, параметры, sys.modules[__name__])
            измерить(профиль, 'независимый журнал: перед эффектом',
                сверить_независимый_журнал, исходные_параметры, выбранный_состав, подготовка, доверенное_поручение=доверенное_поручение)
            сверить_слой()
            def сверить_последний_допуск():
                сверить_независимый_журнал(исходные_параметры, выбранный_состав, подготовка, доверенное_поручение=доверенное_поручение)
                сверить_слой()
                if публикационный is not None:
                    публикационный.сверить(публикация, параметры, sys.modules[__name__])
                if параметры.get('схема') in {'fum.создание-коммита.8', 'fum.создание-коммита.11'}:
                    сверить_обычное_поручение(исходные_параметры, доверенное_поручение, подготовка)
            номер_последнего_допуска = 0
            def последний_допуск():
                nonlocal номер_последнего_допуска
                номер_последнего_допуска += 1
                return измерить(профиль, f'последний допуск: {номер_последнего_допуска}',
                    сверить_последний_допуск)
            return выполнить_эффект(корень, параметры, подготовка, сырая_подготовка, сообщение,
                файл_квитанции, необходимые, допуск, отпечаток_индекса, решение_готовности,
                назначенный, коммиттер, среда, начало, профиль, последний_допуск,
                после_дерева=(lambda: публикационный.последний_адрес(параметры, sys.modules[__name__]))
                    if публикационный is not None else None)
    except (OSError, ValueError, KeyError, TypeError, KeyboardInterrupt, ПрерываниеОперации, отчёты.ОшибкаОтчёта) as причина:
        ошибка = ОшибкаКоммита(str(причина))
        ошибка.длительность_наносекунды = time.perf_counter_ns() - начало
        ошибка.профиль = профиль or [{"стадия": "допуск создания", "исход": "отказ", "длительность_наносекунды": ошибка.длительность_наносекунды}]
        raise ошибка from причина


def выполнить_эффект(корень, параметры, подготовка, сырая_подготовка, сообщение,
        файл_квитанции, необходимые, допуск, отпечаток_индекса, решение_готовности,
        назначенный, коммиттер, среда, начало, профиль, последний_допуск, *,
        читать_гит=None, ожидаемое_дерево=None, после_дерева=None, после_эффекта=None):
    """Единственные write-tree, намерение, обычный commit и сохранение процесса."""
    читать_гит = читать_гит or гит
    последний_допуск()
    дерево = читать_гит(корень, "write-tree").decode().strip()
    требовать(ожидаемое_дерево is None or дерево == ожидаемое_дерево,
        "write-tree отличается от независимо выбранного T")
    if после_дерева is not None:
        после_дерева()
    ожидаемое = {"ветка": параметры["ветка"], "исходный_коммит": параметры["исходный_коммит"],
        "родители": параметры["родители"], "дерево": дерево, "сообщение_sha256": хэш(сообщение),
        "автор": назначенный, "коммиттер": коммиттер, "явные_даты": подготовка["явные_даты"]}
    квитанция = {"схема": "fum.квитанция-создания-коммита.1", "состояние": "намерение",
        "ожидание": ожидаемое, "подготовка_sha256": хэш(сырая_подготовка), "проверки": необходимые,
        "допуск": допуск, "готовность": решение_готовности, "индекс_sha256": отпечаток_индекса,
        "подготовка_наносекунды": time.perf_counter_ns() - начало, "профиль": профиль}
    последний_допуск()
    модели.сохранить_сообщение(файл_квитанции, байты(квитанция).decode())
    try:
        последний_допуск()
        измерить(профиль, "git commit", читать_гит, корень, "commit", "--cleanup=verbatim",
            "--file", параметры["сообщение"], среда=среда)
        квитанция["процесс"] = {"код": 0, "тайм_аут": False,
            "исполнение_завершено": True, "прерывание": None}
    except (ОшибкаКоммита, ValueError) as ошибка:
        квитанция["процесс"] = getattr(ошибка, "процесс", {"код": None,
            "тайм_аут": False, "исполнение_завершено": False, "прерывание": None})
    сообщения._установить(файл_квитанции, байты(квитанция))
    требовать(квитанция["процесс"]["исполнение_завершено"],
        "исход процесса не подтверждён; автоматический повтор запрещён")
    if после_эффекта is not None:
        после_эффекта(квитанция)
        # B повторно читает raw6 и полный stage0 до успешной квитанции.
        голова = читать_гит(корень, "rev-parse", "HEAD").decode().strip()
        итог = проверить_объект(корень, ожидаемое, голова, читать_гит=читать_гит)
        требовать(квитанция["процесс"] == {"код": 0, "тайм_аут": False,
            "исполнение_завершено": True, "прерывание": None}, "процесс B не завершился успешно")
        требовать(читать_гит(корень, "symbolic-ref", "HEAD").decode().strip() == параметры['ветка']
            and читать_гит(корень, "rev-parse", "HEAD").decode().strip() == голова,
            "HEAD/ref B изменились после raw6")
        после_эффекта(квитанция)
        требовать(читать_гит(корень, "symbolic-ref", "HEAD").decode().strip() == параметры['ветка']
            and читать_гит(корень, "rev-parse", "HEAD").decode().strip() == голова,
            "HEAD/ref B изменились после последнего предметного допуска")
        квитанция.update(состояние="проверен", результат=итог, наблюдённый_коммит=голова)
        сообщения._установить(файл_квитанции, байты(квитанция))
        return итог
    return _зафиксировать_новую_квитанцию(корень, квитанция, файл_квитанции,
        обычные_параметры=параметры if обычная_точка(параметры) else None)


def _применить_автообзор(файл_подготовки, итог):
    """Производный приватный результат не отменяет уже проверенный коммит."""
    try:
        каталог = СКРИПТЫ.parents[1] / 'fum-ocenki/scripts'
        sys.path.insert(0, str(каталог))
        import доказательный_обзор
        подготовка = json.loads(прочитать(файл_подготовки, приватный=True))
        доказательный_обзор.применить(файл_подготовки, Path(подготовка['параметры']['квитанция']), ожидаемый=итог)
    except (Exception, KeyboardInterrupt, ПрерываниеОперации) as причина:
        print('FUM: автообзор не получен; проверенный коммит сохранён: ' + str(причина)[:600], file=sys.stderr)


def создать(файл_подготовки, необходимые, *, доверенное_поручение=None, выбранный_состав=None):
    подготовка_маршрута = прочитать_подготовку_для_маршрута(файл_подготовки)
    if базисная_точка(подготовка_маршрута.get("параметры")):
        требовать(выбранный_состав is None, "B не принимает независимый Журнал")
        return вызов_базиса("создать_базис", файл_подготовки, необходимые,
            доверенное_поручение, sys.modules[__name__])
    итог = _создать_проверенный_коммит(файл_подготовки, необходимые,
        доверенное_поручение=доверенное_поручение, выбранный_состав=выбранный_состав)
    # Общий API охватывает новый Git-эффект и восстановление прежней квитанции.
    # Прежний кооперативный замок создателя здесь уже освобождён.
    _применить_автообзор(файл_подготовки, итог)
    return итог



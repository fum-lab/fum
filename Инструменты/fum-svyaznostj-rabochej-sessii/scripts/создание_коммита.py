def сверить_обычное_поручение(параметры, доверенное_поручение, подготовка=None, *, новый_эффект=True):
    if not обычная_точка(параметры):
        требовать(доверенное_поручение is None, 'прежняя схема не принимает независимый выбор обычного поручения')
        требовать(подготовка is None or подготовка.get('схема') not in {'fum.подготовленный-коммит.9', 'fum.подготовленный-коммит.10'},
            'обычная подготовка не является прежним контрактом')
        if not дочерний_режим(параметры):
            требовать(not {'исполнитель', 'выбранное_поручение', 'привязка_поручения'}.intersection(параметры),
                'прежняя схема не принимает поля обычного исполнителя')
        return None
    добавка = {'контракт_журнала'} if параметры.get('схема') == 'fum.создание-коммита.10' else set()
    if повторная_точка(параметры):
        добавка = {'повторный_журнал'}
    требовать(set(параметры) == ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ | {'исполнитель', 'выбранное_поручение'} | добавка,
        'неверные поля обычной дочерней точки')
    if подготовка is not None:
        требовать(подготовка.get('схема') == версия_подготовки(параметры),
            'обычной точке нужна соответствующая подготовка .9 или .10')
    import обычное_поручение
    if повторная_точка(параметры) and not новый_эффект:
        требовать(подготовка is not None and параметры['выбранное_поручение'] == доверенное_поручение,
            'историческое чтение повторной подготовки требует независимый ACT')
        import эффект_повторного_состояния_узла as эффект
        эффект.проверить_историческую_подготовку(Path(параметры['корень']), доверенное_поручение,
            параметры, подготовка)
        return подготовка['привязка_поручения']
    прежние = параметры
    if параметры.get('схема') == 'fum.создание-коммита.10':
        прежние = {к: з for к, з in параметры.items() if к != 'контракт_журнала'}
        прежние['схема'] = 'fum.создание-коммита.7'
        требовать(set(прежние) == ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ | {'исполнитель', 'выбранное_поручение'},
            'служебные поля не являются входом обычного поручения')
    привязка = обычное_поручение.проверить(прежние, доверенное_поручение, новый_эффект=новый_эффект)
    требовать(подготовка is None or подготовка.get('привязка_поручения') == привязка,
        'поручение или нативный снимок изменились после подготовки')
    return привязка


def параметры_готовности(параметры, привязка, журнал=None, повтор=None):
    результат = параметры if привязка is None else {**параметры, 'привязка_поручения': привязка}

    if параметры.get('схема') == 'fum.создание-коммита.10':
        import связность_независимого_журнала as журнал
        результат['допуск_ребёнка'] = журнал.допуск_дочернего_журнала(
            параметры, доверенное_поручение, выбранный_состав)
    return результат




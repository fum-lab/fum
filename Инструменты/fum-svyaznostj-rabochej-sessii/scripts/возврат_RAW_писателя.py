"""Один возврат сохранённого пустого каталога после полной подготовки."""


import contextlib
import fcntl
import hashlib
import os
from pathlib import Path
import stat
import tempfile

import обновление_ожиданий_узла as писатель
import смена_незапечатанной_подготовки as смена
import братиславская_проекция_памяти as перенос

требовать = писатель.требовать


def физический(значение):
    требовать(type(значение) is str, 'нестроковый путь возврата RAW')
    путь = Path(значение)
    требовать(путь.is_absolute() and путь == путь.resolve()
        and not any(п.is_symlink() for п in (путь, *путь.parents)),
        'нефизический путь возврата RAW')
    return путь


def разобрать(вход, параметры, описание):
    писатель.канон.поля(описание, {'схема', 'источник', 'назначение', 'сессия', 'замок', 'идентичность'})
    требовать(описание['схема'] == 'fum.возврат-пустого-RAW.1', 'неизвестный возврат RAW')
    корень, _, _, назначение, сессия = писатель.коммит.отчёты.разрешить_сессию(
        вход['корень'], параметры['запрос'])
    источник = физический(описание['источник'])
    требовать(физический(описание['назначение']) == назначение
        and описание['сессия'] == сессия, 'чужое назначение возврата RAW')
    требовать(not источник.is_relative_to(корень)
        and not any(os.path.lexists(п / '.git') for п in источник.parents),
        'сохранённый RAW находится внутри Git')
    ключ = hashlib.sha256((str(корень)+'\0'+сессия).encode()).hexdigest()
    замок = Path(tempfile.gettempdir()).resolve() / ('fum-check-runs-'+ключ+'.lock')
    требовать(физический(описание['замок']) == замок, 'чужой замок возврата RAW')
    метка = описание['идентичность']
    писатель.канон.поля(метка, {'устройство', 'инод', 'режим', 'владелец'})
    требовать(all(type(метка[к]) is int and метка[к] >= 0 for к in метка)
        and метка['инод'] > 0 and метка['режим'] == 0o755 and метка['владелец'] == os.getuid(),
        'неверная идентичность сохранённого RAW')
    return источник, назначение, замок, метка


def идентичность(с):
    return {'устройство': с.st_dev, 'инод': с.st_ino,
        'режим': stat.S_IMODE(с.st_mode), 'владелец': с.st_uid}


def сверить_каталог(источник, назначение, метка):
    физический(str(источник)); физический(str(назначение))
    требовать(not os.path.lexists(назначение), 'назначение RAW уже существует')
    с = источник.lstat()
    требовать(stat.S_ISDIR(с.st_mode) and идентичность(с) == метка,
        'изменена идентичность сохранённого RAW')
    требовать(not os.listdir(источник), 'сохранённый RAW не пуст')
    родитель = назначение.parent.stat()
    требовать(stat.S_ISDIR(родитель.st_mode) and с.st_dev == родитель.st_dev,
        'возврат RAW требует одной файловой системы и существующего родителя')


@contextlib.contextmanager
def обёртка(вход, параметры, описание):
    """Только существующий штатный lock; вызывается под уже взятым U-lock."""
    источник, назначение, замок, метка = разобрать(вход, параметры, описание)
    исходный = замок.lstat()
    требовать(stat.S_ISREG(исходный.st_mode) and исходный.st_nlink == 1
        and stat.S_IMODE(исходный.st_mode) == 0o600 and исходный.st_uid == os.getuid(),
        'небезопасный существующий замок RAW')
    fd = os.open(замок, os.O_RDWR | os.O_NOFOLLOW)
    взят = False
    try:
        def сверить_замок():
            физический(str(замок))
            открытый = os.fstat(fd); текущий = замок.lstat()
            требовать(открытый.st_dev == текущий.st_dev == исходный.st_dev
                and открытый.st_ino == текущий.st_ino == исходный.st_ino
                and all(stat.S_ISREG(с.st_mode) and с.st_nlink == 1
                    and stat.S_IMODE(с.st_mode) == 0o600 and с.st_uid == os.getuid()
                    for с in (открытый, текущий)), 'подменён существующий замок RAW')
        сверить_замок()
        try: fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as ошибка: raise ValueError('другой запуск держит RAW') from ошибка
        взят = True
        сверить_замок(); сверить_каталог(источник, назначение, метка)
        yield источник, назначение, метка, сверить_замок
    finally:
        if взят: fcntl.flock(fd, fcntl.LOCK_UN)
        os.close(fd)


def предосмотр(вход, параметры, описание):
    """Отказ до G2, без создания файлов; вызывающий уже держит U-lock."""
    with обёртка(вход, параметры, описание): pass


def вернуть(вход, параметры, селектор, описание, итог_смены, сверить_эффект):
    """Один no-replace после genuine seal; отказ не повторяет подготовку."""
    with писатель.привязка(вход, существующая=True) as (путь, намерение):
        требовать(намерение is not None and намерение['стадия'] == 'переподготовлено'
            and намерение['переподготовка']['схема'] == смена.СХЕМА
            and намерение['переподготовка']['параметры'] == селектор
            and итог_смены['схема'] == 'fum.переподготовленные-ожидания.1'
            and итог_смены['операция'] == вход['операция'] and итог_смены['поколение'] == 2
            and итог_смены['коммит'] is None
            and намерение['переподготовка']['запечатано']['хэш'] == итог_смены['запечатано_sha256'],
            'нет genuine sealed G2 для возврата RAW')
        срез = писатель.прочитать_намерение(путь)
        with обёртка(вход, параметры, описание) as (источник, назначение, метка, сверить_замок):
            действующий = писатель.действующий_вход(вход, намерение)
            архив = писатель.канон.разобрать(писатель.прочитать_архив(намерение['переподготовка']['архив']))
            исходная = писатель.коммит.разобрать_подготовку(
                писатель.прочитать_архив(архив['файлы']['подготовка.json']))
            писатель.проверить(действующий, установлен=True)
            подготовка = писатель.проверить_новую_подготовку(вход, параметры, исходная)
            смена.проверить_новое_наблюдение(вход, намерение, подготовка)
            сверить_замок(); сверить_каталог(источник, назначение, метка)
            требовать(писатель.прочитать_намерение(путь) == срез, 'намерение изменилось перед возвратом RAW')
            # ctypes rename на macOS не является os.rename: проверка ставится
            # непосредственно перед принятым syscall, без audit-обхода.
            сверить_эффект()
            перенос.переименовать_устойчиво_без_замены(источник, назначение)
            требовать(not os.path.lexists(источник) and назначение.is_dir()
                and идентичность(назначение.lstat()) == метка, 'неподтверждённый исход возврата RAW')
            сверить_эффект(); сверить_замок()
            требовать(писатель.прочитать_намерение(путь) == срез, 'намерение изменилось после возврата RAW')
            писатель.проверить_модель_подготовки(вход, параметры, подготовка)

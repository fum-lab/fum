"""Приватные успешные сверки содержимого; непрерывность DAG не кэшируется."""
from __future__ import annotations

import os
import re
import time
import uuid
from pathlib import Path

import сообщения_задачи as читатель
import история_пути_гита as гит


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def проверить_хэш(значение):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение), 'неверный SHA кэша свидетельств')


def проверить_ключ(ключ):
    требовать(type(ключ) is dict and set(ключ) == {'экземпляр', 'запись_sha256', 'сообщение_sha256',
        'объект_сообщения_sha256', 'свидетельства'}, 'неверный ключ кэша свидетельств')
    for поле in ('экземпляр', 'запись_sha256', 'сообщение_sha256', 'объект_сообщения_sha256'):
        проверить_хэш(ключ[поле])
    свидетельства = ключ['свидетельства']
    требовать(type(свидетельства) is dict and set(свидетельства) == {'команда', 'ответ', 'основание'}, 'неверные роли свидетельств')
    for состояние in свидетельства.values():
        требовать(type(состояние) is dict and set(состояние) == {'путь', 'режим', 'объект', 'байты_sha256'}, 'неверное состояние свидетельства')
        гит.точный_путь(состояние['путь'])
        требовать(состояние['режим'] in {'100644', '100755'}, 'необычный исторический файл')
        гит.полный_идентификатор(состояние['объект'])
        проверить_хэш(состояние['байты_sha256'])


def основа_проверки(событие, сообщение):
    return {'экземпляр': сообщение['экземпляр'],
        'запись_sha256': читатель._хэш(читатель._байты(событие)),
        'сообщение_sha256': сообщение['позиция']['sha256'],
        'объект_сообщения_sha256': читатель._хэш(читатель._байты(сообщение['сырой_объект']))}


def ключ_проверки(событие, основа, состояния, хэши):
    if any(состояния[роль] is None for роль in ('команда', 'ответ', 'основание')):
        return None
    ключ = {**основа,
        'свидетельства': {роль: {'путь': событие['запись'][роль]['путь'],
            'режим': состояния[роль][0], 'объект': состояния[роль][1],
            'байты_sha256': хэши[состояния[роль][1]]}
            for роль in ('команда', 'ответ', 'основание')}}
    проверить_ключ(ключ)
    return ключ


class СеансСверки:
    def __init__(сам, путь, снимок, корень, реализация, *, без_записи=False):
        сам.путь = None if путь is None else читатель._путь(путь)
        сам.без_записи = без_записи
        сам.идентичность = {'схема': 'fum.кэш-сверки-остатка.1', 'задача': снимок['задача'],
                          'источник': снимок['источник'], 'реализация': реализация}
        сам.профиль = {'перепроверено': 0, 'переиспользовано': 0, 'отказы': 0,
                      'прочитано_байтов': 0, 'записано_байтов': 0, 'чтение_наносекунды': 0,
                      'сверки_наносекунды': 0, 'сохранение_наносекунды': 0}
        if сам.путь is not None:
            требовать(сам.путь.parent.is_dir(), 'каталог приватного кэша отсутствует')
            требовать(not сам.путь.is_relative_to(корень) and
                not any(os.path.lexists(предок / '.git') for предок in сам.путь.parents), 'кэш свидетельств запрещён в Git checkout')
        сам.проверено = сам.прочитать()
        сам.новые = {}

    def прочитать(сам):
        начало = time.perf_counter_ns()
        try:
            if сам.путь is None or not os.path.lexists(сам.путь):
                return {}
            with os.fdopen(os.open(сам.путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
                состояние = os.fstat(поток.fileno())
                читатель._обычный(состояние, приватный=True)
                байты = поток.read()
                требовать(читатель._метка(состояние) == читатель._метка(os.fstat(поток.fileno())) ==
                          читатель._метка(сам.путь.stat()), 'кэш свидетельств изменился при чтении')
            сам.профиль['прочитано_байтов'] += len(байты)
            оболочка = читатель._разобрать(байты)
            требовать(type(оболочка) is dict and set(оболочка) == {'данные', 'sha256'} and
                читатель._байты(оболочка) == байты, 'неверная оболочка кэша свидетельств')
            данные = оболочка['данные']
            требовать(читатель._хэш(читатель._байты(данные)) == оболочка['sha256'], 'неверный хэш кэша свидетельств')
            требовать(type(данные) is dict and set(данные) == {*сам.идентичность, 'проверено'}, 'неверные поля кэша свидетельств')
            требовать(данные['схема'] == сам.идентичность['схема'] and
                данные['задача'] == сам.идентичность['задача'] and данные['источник'] == сам.идентичность['источник'], 'чужой кэш свидетельств')
            требовать(str(uuid.UUID(данные['задача'])) == данные['задача'], 'неверный UUID кэша свидетельств')
            проверить_хэш(данные['источник'])
            проверить_хэш(данные['реализация'])
            требовать(type(данные['проверено']) is dict, 'нет списка проверенных свидетельств')
            for отпечаток, ключ in данные['проверено'].items():
                проверить_ключ(ключ)
                требовать(читатель._хэш(читатель._байты(ключ)) == отпечаток, 'ключ кэша свидетельств изменён')
            return данные['проверено'] if данные['реализация'] == сам.идентичность['реализация'] else {}
        finally:
            сам.профиль['чтение_наносекунды'] += time.perf_counter_ns() - начало

    def сверить(сам, ключ, проверка):
        начало = time.perf_counter_ns()
        try:
            отпечаток = None if ключ is None else читатель._хэш(читатель._байты(ключ))
            if сам.путь is not None and (отпечаток in сам.проверено or отпечаток in сам.новые):
                сам.профиль['переиспользовано'] += 1
                return
            сам.профиль['перепроверено'] += 1
            try:
                проверка()
            except Exception:
                сам.профиль['отказы'] += 1
                raise
            if сам.путь is not None and ключ is not None:
                сам.новые[отпечаток] = ключ
        finally:
            сам.профиль['сверки_наносекунды'] += time.perf_counter_ns() - начало

    def сохранить(сам):
        # Вызывается исключительно после свежей заключительной сверки.
        if сам.путь is None or сам.без_записи or not сам.новые:
            return False
        начало = time.perf_counter_ns()
        try:
            with читатель._замок(сам.путь):
                прежние = сам.прочитать()
                проверено = {**прежние, **сам.новые}
                if проверено != прежние:
                    данные = {**сам.идентичность, 'проверено': проверено}
                    байты = читатель._байты({'данные': данные, 'sha256': читатель._хэш(читатель._байты(данные))})
                    читатель._установить(сам.путь, байты)
                    сам.профиль['записано_байтов'] = len(байты)
            return True
        finally:
            сам.профиль['сохранение_наносекунды'] = time.perf_counter_ns() - начало

def загрузить_охват():
    описание = importlib.util.spec_from_file_location('охват_обычного_поручения',
        Path(__file__).with_name('сверить-материалы-этапа.py'))
    модуль = importlib.util.module_from_spec(описание)
    sys.modules[описание.name] = модуль
    описание.loader.exec_module(модуль)
    return модуль


охват = загрузить_охват()


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def отметка(профиль, имя, начало):
    конец = time.perf_counter_ns()
    if профиль is not None:
        профиль.setdefault(имя, []).append(конец - начало)
    return конец


def идентичность(значение):
    требовать(type(значение) is str and str(uuid.UUID(значение)) == значение,
        'нужен канонический UUID')
    return значение


def путь(корень, имя, кэш=None):
    история.точный_путь(имя)
    требовать(not any(часть.startswith('.') for часть in Path(имя).parts),
        'скрытый путь не является областью обычного поручения')
    return охват.точный_путь(корень, имя, кэш)


def выбор(данные):
    контракт.поля(данные, {'координатор', 'исполнитель', 'коммит', 'путь', 'sha256'})
    идентичность(данные['координатор'])
    идентичность(данные['исполнитель'])
    требовать(данные['координатор'] != данные['исполнитель'], 'ROOT и own UUID должны различаться')
    история.полный_идентификатор(данные['коммит'])
    история.точный_путь(данные['путь'])
    требовать(type(данные['sha256']) is str and re.fullmatch('[0-9a-f]{64}', данные['sha256']),
        'нужен полный SHA256 поручения')


def прочитать_акт(корень, независимый, *, новый_эффект=True):
    выбор(независимый)
    путь(корень, независимый['путь'])
    данные = делегация.сверить_источник(корень, независимый)
    акт = контракт.разобрать_байты(данные)
    новый = акт.get('схема') == 'fum.поручение-дочерней-контрольной-точки.2'
    контракт.поля(акт, {'схема', 'координатор', 'исполнитель', 'ветка', 'область',
        'постановка', 'хэш_нативного_поручения'} | ({'полномочия_узла'} if новый else set()))
    требовать(новый or акт['схема'] == 'fum.поручение-дочерней-контрольной-точки.1',
        'неверная схема обычного поручения')
    требовать(all(акт[поле_идентичности] == независимый[поле_идентичности] for поле_идентичности in ('координатор', 'исполнитель')),
        'акт не совпадает с независимыми UUID')
    контракт.поля(акт['постановка'], {'коммит', 'путь', 'sha256'})
    выбор_постановки = {**акт['постановка'], 'координатор': акт['координатор'],
        'исполнитель': акт['исполнитель']}
    выбор(выбор_постановки)
    путь(корень, выбор_постановки['путь'])
    делегация.сверить_источник(корень, выбор_постановки)
    требовать(type(акт['хэш_нативного_поручения']) is str
        and re.fullmatch('[0-9a-f]{64}', акт['хэш_нативного_поручения']),
        'неверный SHA первоначального нативного поручения')
    if новый:
        import полномочия_ветки_состояния_узла as полномочия
        полномочия.проверить_акт(корень, акт, новый_эффект=новый_эффект)
        требовать(полномочия.гит.предок(корень, акт['полномочия_узла']['коммит'], независимый['коммит']),
            'полномочия не приняты в историю ACT')
    return акт


def проверить_область(корень, область, цели):
    требовать(type(область) is list and область and type(цели) is list and цели,
        'нужны конечные область и цели')
    ключи = set()
    кэш_путей = {}
    for имя in область:
        требовать(type(имя) is str and имя, 'пустая область поручения')
        простой = имя[:-1] if имя.endswith('/') else имя
        путь(корень, простой, кэш_путей)
        требовать(простой not in {'Журнал', 'Индексы', 'Правила', 'Инструменты', 'Планирование',
            'Приложения', 'Прототипы', 'Документация', 'Память', 'Источники', 'Зависимости'},
            'широкая служебная область запрещена')
        ключ = unicodedata.normalize('NFC', простой).casefold()
        требовать(ключ not in ключи, 'неоднозначные имена области')
        ключи.add(ключ)
    for цель in цели:
        путь(корень, цель, кэш_путей)
        требовать(any(цель.startswith(имя) if имя.endswith('/') else цель == имя
            for имя in область), 'цель выходит из закреплённой области: ' + цель)


def _гит(корень, *аргументы):
    ответ_гита = subprocess.run(['git', '--no-optional-locks', '--no-replace-objects', '-C', str(корень), *аргументы],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=120)
    требовать(ответ_гита.returncode == 0, 'чтение Git отказало')
    return ответ_гита.stdout.decode().strip()


def сверить_единый_снимок(источник, начало, поручение):
    """Оба префикса должны существовать одновременно в одном физическом файле."""
    граница = поручение['граница']
    требовать(type(граница) is int and 0 < начало['граница'] <= граница <= 16 * 1024 * 1024,
        'неверные границы нативного снимка')
    with os.fdopen(os.open(источник, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        состояние = os.fstat(поток.fileno())
        требовать(stat.S_ISREG(состояние.st_mode), 'нативный источник не является обычным файлом')
        байты = поток.read(граница)
        требовать(len(байты) == граница and hashlib.sha256(байты).hexdigest() == поручение['sha256']
            and hashlib.sha256(байты[:начало['граница']]).hexdigest() == начало['sha256'],
            'начало и поручение не составляют единый нативный снимок')
        после = Path(источник).stat()
        требовать((состояние.st_dev, состояние.st_ino) == (после.st_dev, после.st_ino)
            and после.st_size >= граница, 'нативный файл подменён или усечён')
        поток.seek(0)
        требовать(поток.read(граница) == байты, 'нативный снимок изменился при сверке')


def _проверить(параметры, доверенное_поручение, *, новый_эффект=True, профиль=None):
    отметка_начала = time.perf_counter_ns()
    новый = type(параметры) is dict and параметры.get('схема') == 'fum.создание-коммита.8'
    требовать(type(параметры) is dict and (новый or параметры.get('схема') == 'fum.создание-коммита.7')
        and параметры.get('режим') == 'контрольная-точка', 'нужна обычная дочерняя контрольная точка .7 или state .8')
    требовать(доверенное_поручение is not None, 'нет независимого выбора поручения')
    выбор(доверенное_поручение)
    требовать(параметры.get('выбранное_поручение') == доверенное_поручение,
        'копия выбора отличается от независимого входа')
    корневая_задача = идентичность(параметры['задача'])
    исполнитель = идентичность(параметры['исполнитель'])
    требовать(корневая_задача == доверенное_поручение['координатор']
        and исполнитель == доверенное_поручение['исполнитель'] and os.environ.get('CODEX_THREAD_ID') == исполнитель,
        'неверные ROOT, own UUID или среда процесса')
    запрещены = {'GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR',
        'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES', 'GIT_CONFIG_PARAMETERS',
        'GIT_CONFIG_COUNT', 'GIT_REPLACE_REF_BASE', 'GIT_SHALLOW_FILE', 'GIT_NAMESPACE'}
    требовать(not запрещены.intersection(os.environ), 'перенаправление Git запрещено')
    отметка_начала = отметка(профиль, 'идентичности', отметка_начала)
    корень_исполнителя = Path(параметры['корень'])
    требовать(корень_исполнителя.is_absolute() and корень_исполнителя == корень_исполнителя.resolve() and _гит(корень_исполнителя, 'rev-parse', '--show-toplevel') == str(корень_исполнителя),
        'нужен физический корень своего checkout')
    акт = прочитать_акт(корень_исполнителя, доверенное_поручение, новый_эффект=новый_эффект)
    отметка_начала = отметка(профиль, 'корень-и-акт', отметка_начала)
    ветка = параметры['ветка']
    if новый:
        import полномочия_ветки_состояния_узла as полномочия
        требовать(акт['схема'] == 'fum.поручение-дочерней-контрольной-точки.2', 'state .8 требует независимый ACT .2')
        проверенные = полномочия.проверить_дерево(корень_исполнителя, исполнитель, ветка,
            акт['полномочия_узла'], исходный_коммит=параметры['исходный_коммит'],
            цели=параметры['разрешённые_цели'], новый_эффект=новый_эффект)
    else:
        требовать(акт['схема'] == 'fum.поручение-дочерней-контрольной-точки.1', 'старая .7 требует прежний ACT .1')
    требовать(type(ветка) is str and (новый or ветка.startswith('refs/heads/codex/')) and ветка == акт['ветка']
        and _гит(корень_исполнителя, 'symbolic-ref', 'HEAD') == ветка, 'неверный полный ref исполнителя')
    деревья = _гит(корень_исполнителя, 'worktree', 'list', '--porcelain').split('\n\n')
    владельцы = [дерево for дерево in деревья if 'branch ' + ветка in дерево.splitlines()]
    требовать(len(владельцы) == 1 and владельцы[0].splitlines()[0] == 'worktree ' + str(корень_исполнителя),
        'нет единственного собственного дерева ветки')
    отметка_начала = отметка(профиль, 'ветка-и-владение', отметка_начала)
    источник = параметры['источник_модели']
    нативный_файл = Path(источник)
    требовать(нативный_файл.is_absolute() and нативный_файл == нативный_файл.resolve(),
        'нужен абсолютный физический путь native JSONL')
    начало, контекст, граница = постановка.прочитать_начало_источника(источник)
    требовать(начало.get('id') == исполнитель and начало.get('thread_source') == 'agent_created_thread'
        and начало.get('cwd') == контекст.get('cwd') == str(корень_исполнителя), 'чужое нативное начало')
    требовать(type(начало.get('git')) is dict
        and начало['git'].get('commit_hash') == акт['постановка']['коммит'], 'неверный начальный C')
    нативное_поручение = постановка.прочитать_нативное_поручение(источник, кодирование='буквальный')
    требовать(нативное_поручение['отправитель'] == корневая_задача
        and hashlib.sha256(нативное_поручение['текст'].encode()).hexdigest() == акт['хэш_нативного_поручения'],
        'первое нативное поручение не соответствует акту координатора')
    отметка_начала = отметка(профиль, 'нативные-префиксы', отметка_начала)
    история.полный_идентификатор(параметры['исходный_коммит'])
    if новый_эффект:
        требовать(_гит(корень_исполнителя, 'rev-parse', 'HEAD') == параметры['исходный_коммит'], 'HEAD этапа изменился')
    _гит(корень_исполнителя, 'merge-base', '--is-ancestor', акт['постановка']['коммит'], 'HEAD')
    цели = параметры['разрешённые_цели']
    требовать(type(цели) is list and len(цели) == len(set(цели)), 'нужны неповторяющиеся точные цели')
    запрос = параметры['запрос']
    требовать(type(запрос) is str and охват.СВЯЗНОСТЬ.is_request_file(корень_исполнителя / запрос, корень_исполнителя),
        'нужен адрес собственного Журнала')
    требовать(type(параметры['история_модели']) is str
        and параметры['история_модели'].startswith(str(Path(запрос).parent / 'материалы') + '/'),
        'история модели должна находиться в материалах своего этапа')
    проверить_область(корень_исполнителя, акт['область'], [*цели, запрос,
        str(Path(запрос).with_name('отчёт.md')), параметры['история_модели']])
    отметка_начала = отметка(профиль, 'HEAD-и-область', отметка_начала)
    сверить_единый_снимок(источник, граница, нативное_поручение['источник'])
    отметка(профиль, 'единый-снимок', отметка_начала)
    результат = {'выбранное_поручение': доверенное_поручение,
        'нативное_начало': граница, 'нативное_поручение': нативное_поручение['источник']}
    if новый:
        результат['полномочия_узла'] = {'источник': акт['полномочия_узла'], 'значение': проверенные}
    return результат


def проверить(параметры, доверенное_поручение, *, новый_эффект=True, профиль=None):
    """Единый отказ читателя без создания файлов, истории модели или Git-эффекта."""
    начало = time.perf_counter_ns()
    try:
        return _проверить(параметры, доверенное_поручение, новый_эффект=новый_эффект, профиль=профиль)
    except (история.ОшибкаОтчёта, постановка.ОшибкаПриёма, OSError, KeyError,
            TypeError, subprocess.TimeoutExpired) as ошибка:
        raise ValueError(str(ошибка)) from ошибка
    finally:
        отметка(профиль, 'весь-читатель', начало)

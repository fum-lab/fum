def проверить_цель(путь):
    создатель.требовать(путь.is_absolute() and путь == путь.resolve()
        and not any(п.is_symlink() for п in (путь, *путь.parents)), 'нефизический atomic output')
    корень = Path(параметры['корень'])
    if путь.is_relative_to(корень):
        создатель.требовать(путь.relative_to(корень).as_posix() in параметры['разрешённые_цели'],
            'atomic output вне назначенных целей')
    else:
        создатель.требовать(путь in приватные_цели or путь.is_relative_to(Path(настройки['готовность'])),
            'чужой приватный atomic output')
        создатель.требовать(not any(os.path.lexists(п / '.git') for п in путь.parents),
            'приватный atomic output в Git')


def записать_без_буфера(дескриптор, данные):
    позиция = 0
    while позиция < len(данные):
        сверить_эффект()
        записано = os.write(дескриптор, данные[позиция:])
        создатель.требовать(type(записано) is int and записано > 0, 'неполная приватная запись')
        позиция += записано
    сверить_эффект()
    os.fsync(дескриптор)


def сохранить_сообщение(назначение, текст):
    путь = создатель.модели._путь(назначение)
    проверить_цель(путь)
    создатель.требовать(путь in выходы, 'чужой приватный выход')
    создатель.модели.чтение._требовать(not any(os.path.lexists(п / '.git') for п in путь.parents),
        'приватный выход запрещён в Git')
    сверить_эффект()
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        записать_без_буфера(дескриптор, текст.encode('utf-8'))
    finally:
        os.close(дескриптор)


def установить_без_буфера(путь, данные):
    # Тот же атомарный алгоритм; нет записи при close/exception unwinding.
    проверить_цель(путь)
    сверить_эффект()
    дескриптор, имя = tempfile.mkstemp(dir=путь.parent, prefix='.сообщения-')
    временный = Path(имя)
    try:
        try:
            записать_без_буфера(дескриптор, данные)
        finally:
            os.close(дескриптор)
        сверить_эффект()
        os.replace(временный, путь)
        сверить_эффект()
        каталог = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            сверить_эффект()
            os.fsync(каталог)
        finally:
            os.close(каталог)
    finally:
        if временный.exists():
            сверить_эффект()
            временный.unlink()


создатель.модели.сохранить_сообщение = сохранить_сообщение
создатель.сообщения._установить = установить_без_буфера

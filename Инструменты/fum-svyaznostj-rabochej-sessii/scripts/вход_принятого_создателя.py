def прочитать_квитанцию():
    сырая = создатель.прочитать(параметры['подготовка'], приватный=True)
    подготовка = создатель.разобрать_подготовку(сырая)
    привязка = создатель.сверить_обычное_поручение(подготовка['параметры'], выбранные['поручение'],
        подготовка, новый_эффект=False)
    связанные = создатель.параметры_готовности(подготовка['параметры'], привязка)
    корень = создатель.адрес_дерева(связанные)
    файл = создатель.путь(связанные['квитанция'], приватный=True)
    сырая_квитанция = создатель.прочитать(файл, приватный=True)
    квитанция = создатель.сообщения._разобрать(сырая_квитанция)
    создатель.требовать(квитанция['подготовка_sha256'] == создатель.хэш(сырая), 'квитанция другой подготовки')
    создатель.сверить_ожидание_квитанции(квитанция, подготовка, связанные)
    итог = создатель.восстановить(корень, квитанция, файл)
    создатель.требовать(создатель.прочитать(файл, приватный=True) == сырая_квитанция
        and создатель.прочитать(параметры['подготовка'], приватный=True) == сырая,
        'подготовка или квитанция изменились при повторе')
    return итог



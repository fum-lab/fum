"""Чистая диагностика предъявленных снимков; разрешений на эффекты не выдаёт."""
import hashlib
import io
import re
import uuid

import автор_коммита as автор
import история_модели as история


ПОЛЯ_ИСТОРИИ = frozenset({'схема', 'задача', 'источник', 'граница', 'sha256',
    'число_наблюдений', 'события', 'пропуски', 'последнее',
    'переключения_между_наблюдениями_известны', 'размер_снимка', 'неполный_хвост'})
ПОЛЯ_НАБЛЮДЕНИЯ = frozenset({'модель', 'усилие', 'время', 'позиция', 'причина', 'инициатор'})
ПОЛЯ_ПОДТВЕРЖДЕНИЯ = frozenset({'схема', 'исходная_история_sha256',
    'текущая_история_sha256', 'сырые_байты_снимка',
    'дописано_после_исходного_снимка', 'дописано_после_текущего_снимка'})


def _требовать(условие):
    if not условие:
        raise ValueError('неверная закрытая структура входа классификации')


def _поля(значение, поля):
    _требовать(type(значение) is dict and all(type(к) is str for к in значение)
        and set(значение) == поля)


def _число(значение):
    _требовать(type(значение) is int and значение >= 0)


def _строка(значение):
    _требовать(type(значение) is str and история._строка(значение))


def _отпечаток(значение):
    _требовать(type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение) is not None)


def _позиция(значение):
    _поля(значение, {'начало', 'конец', 'sha256'})
    _число(значение['начало']); _число(значение['конец'])
    _требовать(значение['начало'] < значение['конец'])
    _отпечаток(значение['sha256'])


def _пара(значение):
    _поля(значение, {'модель', 'усилие'})
    _строка(значение['модель']); _строка(значение['усилие'])


def _наблюдение(значение, *, событие=False):
    _поля(значение, ПОЛЯ_НАБЛЮДЕНИЯ | ({'предыдущее', 'вид'} if событие else set()))
    for имя in ('модель', 'усилие', 'время', 'причина', 'инициатор'):
        _строка(значение[имя])
    _позиция(значение['позиция'])
    if событие:
        _требовать(type(значение['вид']) is str and значение['вид'] in {
            'первое наблюдение', 'наблюдение после пропуска', 'смена наблюдаемой пары'})
        if значение['предыдущее'] is not None:
            _пара(значение['предыдущее'])


def _проверить_историю(значение):
    _поля(значение, ПОЛЯ_ИСТОРИИ)
    _требовать(значение['схема'] == 'fum.история-модели.1')
    _требовать(type(значение['задача']) is str)
    try:
        _требовать(str(uuid.UUID(значение['задача'])) == значение['задача'])
    except (ValueError, AttributeError):
        raise ValueError('неверный UUID истории классификации') from None
    for имя in ('источник', 'sha256'):
        _отпечаток(значение[имя])
    for имя in ('граница', 'размер_снимка', 'неполный_хвост', 'число_наблюдений'):
        _число(значение[имя])
    _требовать(0 < значение['граница'] <= значение['размер_снимка']
        and значение['неполный_хвост'] == значение['размер_снимка'] - значение['граница'])
    _требовать(значение['переключения_между_наблюдениями_известны'] is False
        and type(значение['события']) is list and type(значение['пропуски']) is list)
    for событие in значение['события']:
        _наблюдение(событие, событие=True)
    for пропуск in значение['пропуски']:
        _требовать(type(пропуск) is dict and type(пропуск.get('вид')) is str)
        if пропуск['вид'] == 'повреждённая строка JSONL':
            _поля(пропуск, {'позиция', 'вид'})
        else:
            _требовать(пропуск['вид'] == 'неполное наблюдение turn_context')
            _поля(пропуск, {'позиция', 'вид', 'модель', 'усилие', 'время'})
            for имя in ('модель', 'усилие', 'время'):
                _строка(пропуск[имя])
        _позиция(пропуск['позиция'])
    if значение['последнее'] is not None:
        _наблюдение(значение['последнее'])


def _проверить_подтверждение(значение):
    _поля(значение, ПОЛЯ_ПОДТВЕРЖДЕНИЯ)
    _требовать(значение['схема'] == 'fum.проверка-продолжения-наблюдений-модели.1'
        and type(значение['сырые_байты_снимка']) is bytes)
    for имя in ('исходная_история_sha256', 'текущая_история_sha256'):
        _отпечаток(значение[имя])
    for имя in ('дописано_после_исходного_снимка', 'дописано_после_текущего_снимка'):
        _число(значение[имя])


def _хэш_истории(значение):
    return hashlib.sha256(история.чтение._байты(значение)).hexdigest()


def _хэш_префикса(сырые, граница):
    return hashlib.sha256(memoryview(сырые)[:граница]).hexdigest()


def _восстановить_историю(сырые, задача, размер):
    return история._приём(io.BytesIO(сырые), задача, None, размер,
        {'прочитано_байтов': 0, 'разобрано_строк': 0})


def _известная_пара(значение):
    return all(автор.проверить_токен(значение[имя]) for имя in ('модель', 'усилие'))


def _известная_история(значение):
    if значение['последнее'] is None or not _известная_пара(значение['последнее']):
        return False
    for событие in значение['события']:
        if not _известная_пара(событие) or (событие['предыдущее'] is not None
                and not _известная_пара(событие['предыдущее'])):
            return False
    return True


def классифицировать_продолжение(исходная_история, текущая_история, подтверждение):
    """Сравнить предъявленные данные без I/O после загрузки; входы не изменяются."""
    _проверить_историю(исходная_история)
    _проверить_историю(текущая_история)
    _проверить_подтверждение(подтверждение)
    исходный_хэш = _хэш_истории(исходная_история)
    текущий_хэш = _хэш_истории(текущая_история)
    def результат(диагноз, причина, наблюдения=None, события=None):
        return {'схема': 'fum.классификация-продолжения-наблюдений-модели.1',
            'диагноз': диагноз, 'причины': [причина], 'новых_наблюдений': наблюдения,
            'новых_событий': события, 'исходная_история_sha256': исходный_хэш,
            'текущая_история_sha256': текущий_хэш}
    def неизвестность(причина):
        return результат('неизвестность', причина)
    if исходный_хэш != подтверждение['исходная_история_sha256'] or текущий_хэш != подтверждение['текущая_история_sha256']:
        return неизвестность('несвязанная_история')
    if any(исходная_история[имя] != текущая_история[имя] for имя in ('задача', 'источник')):
        return неизвестность('иная_идентичность_источника')
    сырые = подтверждение['сырые_байты_снимка']
    if len(сырые) != текущая_история['размер_снимка'] or исходная_история['размер_снимка'] > len(сырые) or исходная_история['граница'] > текущая_история['граница']:
        return неизвестность('неподтверждённая_полная_граница')
    if _хэш_префикса(сырые, исходная_история['граница']) != исходная_история['sha256'] or _хэш_префикса(сырые, текущая_история['граница']) != текущая_история['sha256']:
        return неизвестность('изменённый_сырой_префикс')
    if подтверждение['дописано_после_исходного_снимка'] or подтверждение['дописано_после_текущего_снимка']:
        return неизвестность('дописание_после_снимка')
    if any(значение['пропуски'] or значение['неполный_хвост'] for значение in (исходная_история, текущая_история)):
        return неизвестность('неполное_наблюдение')
    восстановленные = []
    for значение, отпечаток in ((исходная_история, исходный_хэш), (текущая_история, текущий_хэш)):
        try:
            восстановленная = _восстановить_историю(сырые, значение['задача'], значение['размер_снимка'])
        except (история.чтение.ОшибкаСообщений, ValueError):
            return неизвестность('неподтверждённая_история')
        if _хэш_истории(восстановленная) != отпечаток:
            return неизвестность('неподтверждённая_история')
        восстановленные.append(восстановленная)
    исходная_проверенная, текущая_проверенная = восстановленные
    if not all(_известная_история(значение) for значение in восстановленные):
        return неизвестность('неизвестная_модельная_пара')
    новых_наблюдений = текущая_проверенная['число_наблюдений'] - исходная_проверенная['число_наблюдений']
    новые_события = текущая_проверенная['события'][len(исходная_проверенная['события']):]
    исходная_пара = tuple(исходная_проверенная['последнее'][имя] for имя in ('модель', 'усилие'))
    if any(tuple(событие[имя] for имя in ('модель', 'усилие')) != исходная_пара for событие in новые_события):
        return результат('наблюдаемое_переключение', 'смена_в_добавленной_области', новых_наблюдений, len(новые_события))
    if новых_наблюдений:
        return результат('добавлены_наблюдения_той_же_пары', 'одинаковые_добавленные_наблюдения', новых_наблюдений, len(новые_события))
    return результат('неизменный', 'новых_наблюдений_нет', 0, 0)

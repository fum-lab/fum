"""Адресная смена полной незапечатанной подготовки после дрейфа модели."""
import argparse
import copy
import os
from pathlib import Path
import stat
import sys

import обновление_ожиданий_узла as писатель

канон = писатель.канон
требовать = писатель.требовать
СХЕМА = 'fum.переход-переподготовки-ожиданий.2'
ИМЕНА = {'параметры.json', 'подготовка.json', 'сообщение.txt',
    'прежний-вызов-подготовки.json', 'история-модели.json', 'курсор-модели.json'}


def каталог_поколения(вход, намерение):
    корень = Path(вход['каталог_операции']) / 'переподготовка'
    return корень / 'поколения/2' if намерение['переподготовка']['схема'] == СХЕМА else корень


def проверить_запрос(вход, запрос):
    канон.поля(запрос, {'схема', 'хэш_входа', 'намерение_sha256',
        'прежние_параметры', 'новые_параметры', 'основание_дрейфа'})
    требовать(запрос['схема'] == 'fum.смена-незапечатанной-подготовки.1', 'неизвестная смена подготовки')
    for поле in ('хэш_входа', 'намерение_sha256'): канон.полный_хэш(запрос[поле])
    требовать(запрос['хэш_входа'] == писатель.хэш(писатель.кодировать(вход)), 'чужой вход смены')
    дрейф = запрос['основание_дрейфа']
    канон.поля(дрейф, {'последнее', 'число_наблюдений'})
    требовать(type(дрейф['число_наблюдений']) is int and дрейф['число_наблюдений'] > 0
        and type(дрейф['последнее']) is dict, 'нужно полное основание дрейфа')


def сверить_сохранённые(параметры, файлы):
    """Старые last/count сверяются с архивом, а не с новой живой историей."""
    п = канон.разобрать(файлы['подготовка.json'])
    писатель.коммит.разобрать_подготовку(файлы['подготовка.json'])
    история = канон.разобрать(файлы['история-модели.json'])
    курсор = канон.разобрать(файлы['курсор-модели.json'])
    требовать(set(курсор) == {'данные', 'sha256'}
        and писатель.коммит.модели.чтение._хэш(писатель.коммит.модели.чтение._байты(курсор['данные']))
            == курсор['sha256'], 'повреждён сохранённый курсор')
    требовать(п['схема'] == писатель.коммит.версия_подготовки(параметры) and п['параметры'] == параметры
        and писатель.хэш(файлы['сообщение.txt']) == п['сообщение_sha256']
        and писатель.хэш(файлы['история-модели.json']) == п['история_sha256']
        and not курсор['данные']['подготовлено'] and курсор['данные']['история'] == история
        and история['число_наблюдений'] == п['наблюдений'] and история['последнее'] == п['модель'],
        'неполная прежняя подготовка; pending/unknown')
    return п


def сверить_цепочку(вход, намерение):
    переход = намерение['переподготовка']
    канон.поля(переход, {'схема', 'параметры', 'архив', 'запечатано', 'предыдущее'})
    требовать(переход['схема'] == СХЕМА, 'неизвестное поколение')
    каталог = каталог_поколения(вход, намерение)
    требовать(Path(переход['предыдущее']['путь']) == каталог / 'предыдущее-поколение.json',
        'чужой адрес цепочки поколений')
    архив = канон.разобрать(писатель.прочитать_архив(переход['предыдущее']))
    канон.поля(архив, {'схема', 'намерение', 'запрос', 'файлы'})
    требовать(архив['схема'] == 'fum.архив-незапечатанного-поколения.1' and set(архив['файлы']) == ИМЕНА,
        'неизвестный архив поколения')
    запрос = архив['запрос']; проверить_запрос(вход, запрос)
    прежнее = архив['намерение']; канон.поля(прежнее, писатель.ПОЛЯ_НАМЕРЕНИЯ | {'переподготовка'})
    старый = прежнее['переподготовка']; канон.поля(старый, {'схема', 'параметры', 'архив', 'запечатано'})
    требовать(прежнее['схема'] == 'fum.намерение-обновления-ожиданий.2'
        and прежнее['стадия'] == 'переподготовка' and прежнее['хэш_подготовки'] is None
        and прежнее['проверки'] is None and старый['схема'] == 'fum.переход-переподготовки-ожиданий.1'
        and старый['запечатано'] is None and старый['архив'] == переход['архив']
        and старый['параметры'] == запрос['прежние_параметры']
        and переход['параметры'] == запрос['новые_параметры']
        and писатель.хэш(писатель.кодировать(прежнее)) == запрос['намерение_sha256']
        and all(прежнее[п] == намерение[п] for п in писатель.ПОЛЯ_НАМЕРЕНИЯ
            if п not in {'стадия', 'хэш_подготовки', 'проверки'}), 'подменён предшественник поколения')
    файлы = {}
    for имя, ссылка in архив['файлы'].items():
        требовать(Path(ссылка['путь']) == каталог / имя, 'чужой адрес архивного файла')
        файлы[имя] = писатель.прочитать_архив(ссылка)
    параметры = канон.разобрать(писатель.приватная_ссылка(старый['параметры']))
    требовать(файлы['параметры.json'] == писатель.приватная_ссылка(старый['параметры'])
        and файлы['подготовка.json'] == писатель.прочитать(параметры['подготовка'])
        and файлы['сообщение.txt'] == писатель.прочитать(параметры['сообщение'])
        and файлы['прежний-вызов-подготовки.json'] == писатель.прочитать(
            Path(вход['каталог_операции']) / 'переподготовка/вызов-подготовки.json')
        == писатель.кодировать({'схема': 'fum.начатая-переподготовка-ожиданий.1',
            'параметры': старый['параметры'], 'хэш_входа': намерение['хэш_входа']}),
        'изменены прежние свидетельства поколения')
    сверить_сохранённые(параметры, файлы)
    return старый, файлы, запрос


def проверить_новое_наблюдение(вход, намерение, подготовка):
    if намерение['переподготовка']['схема'] != СХЕМА: return
    _, _, запрос = сверить_цепочку(вход, намерение)
    дрейф = запрос['основание_дрейфа']
    требовать(подготовка['модель'] == дрейф['последнее']
        and подготовка['наблюдений'] == дрейф['число_наблюдений'], 'новое поколение не равно адресному наблюдению')


def сменить_подготовку(вход, запрос):
    """Одна G1→G2; старый unknown, seal и первая попытка не обходятся."""
    проверить_запрос(вход, запрос)
    with писатель.привязка(вход, существующая=True) as (путь, намерение):
        требовать(намерение is not None and намерение['стадия'] == 'переподготовка'
            and намерение['хэш_подготовки'] is None and намерение['проверки'] is None
            and писатель.хэш(писатель.прочитать_намерение(путь)) == запрос['намерение_sha256'],
            'нужно точное незапечатанное намерение до первой попытки')
        переход = намерение['переподготовка']
        канон.поля(переход, {'схема', 'параметры', 'архив', 'запечатано'})
        требовать(переход['схема'] == 'fum.переход-переподготовки-ожиданий.1'
            and переход['запечатано'] is None and переход['параметры'] == запрос['прежние_параметры'],
            'смена разрешает только незапечатанное поколение 1')
        корень, _, _, _, _ = писатель.проверить(вход, установлен=True)
        прежние, старые = писатель.параметры_переподготовки(вход, переход['параметры'])
        _, новые = писатель.параметры_переподготовки(вход, запрос['новые_параметры'])
        исходный_архив = писатель.сверить_архив_переподготовки(вход, намерение, прежние)
        старый_каталог = Path(вход['каталог_операции']) / 'переподготовка'
        требовать(not os.path.lexists(старый_каталог / 'запечатано.json')
            and not any(os.path.lexists(п['квитанция']) for п in (прежние, старые, новые)),
            'seal или квитанция запрещают смену')
        защищённые = {Path(старые[к]) for к in писатель.ВЫХОДЫ_ПОДГОТОВКИ} | {
            Path(переход['параметры']['путь'])}
        требовать(not защищённые.intersection(Path(новые[к]) for к in писатель.ВЫХОДЫ_ПОДГОТОВКИ)
            and запрос['новые_параметры']['путь'] != переход['параметры']['путь']
            and not any(os.path.lexists(новые[к]) for к in писатель.ВЫХОДЫ_ПОДГОТОВКИ),
            'выходы пересекают первое поколение или уже существуют')
        сырые = {'параметры.json': писатель.приватная_ссылка(переход['параметры']),
            'подготовка.json': писатель.прочитать(старые['подготовка']),
            'сообщение.txt': писатель.прочитать(старые['сообщение']),
            'прежний-вызов-подготовки.json': писатель.прочитать(старый_каталог / 'вызов-подготовки.json'),
            'история-модели.json': писатель.читатель.прочитать_файл(корень / старые['история_модели'],
                предел=писатель.читатель.ПРЕДЕЛ), 'курсор-модели.json': писатель.прочитать(старые['кэш_модели'])}
        старая = сверить_сохранённые(старые, сырые)
        genuine, _ = писатель.коммит.прочитать_подготовку_готовности(Path(старые['подготовка']),
            доверенное_поручение=вход['акт'])
        требовать(genuine == старая and писатель.коммит.команды(старые) == старая['команды']
            and сырые['прежний-вызов-подготовки.json'] == писатель.кодировать({
                'схема': 'fum.начатая-переподготовка-ожиданий.1', 'параметры': переход['параметры'],
                'хэш_входа': намерение['хэш_входа']}), 'неполный genuine предшественник')
        исходная = канон.разобрать(исходный_архив['подготовка.json'])
        писатель.проверить_идентичности_переподготовки(вход, исходная, старая)
        def сверить_перед_переходом():
            модель = писатель.коммит.наблюдать_модель(старые, без_записи=True)
            требовать(модель['новых_наблюдений'] > 0 and модель['число_наблюдений'] > старая['наблюдений']
                and {'последнее': модель['последнее'], 'число_наблюдений': модель['число_наблюдений']}
                    == запрос['основание_дрейфа'], 'нет адресного настоящего дрейфа')
            требовать(писатель.прочитать(старые['кэш_модели']) == сырые['курсор-модели.json']
                and писатель.читатель.прочитать_файл(корень / старые['история_модели'],
                    предел=писатель.читатель.ПРЕДЕЛ) == сырые['история-модели.json']
                and писатель.прочитать(старые['подготовка']) == сырые['подготовка.json']
                and писатель.прочитать(старые['сообщение']) == сырые['сообщение.txt'], 'дрейф сохранённых RAW')
            писатель.проверить(вход, установлен=True)
            писатель.проверить_идентичности_переподготовки(вход, исходная, старая)
        сверить_перед_переходом()
        каталог = старый_каталог / 'поколения/2'
        требовать(not os.path.lexists(каталог), 'поколение 2 уже начато; исход unknown')
        for адрес in (каталог.parent, каталог):
            if not os.path.lexists(адрес): адрес.mkdir(mode=0o700)
            канон.физический_путь(адрес)
            требовать(stat.S_IMODE(адрес.stat().st_mode) == 0o700, 'неприватное поколение')
        архив = {'схема': 'fum.архив-незапечатанного-поколения.1',
            'намерение': copy.deepcopy(намерение), 'запрос': copy.deepcopy(запрос),
            'файлы': {имя: писатель.неизменяемые_байты(каталог / имя, данные) for имя, данные in сырые.items()}}
        ссылка = писатель.неизменяемые_байты(каталог / 'предыдущее-поколение.json', писатель.кодировать(архив))
        новое = {**намерение, 'переподготовка': {'схема': СХЕМА,
            'параметры': copy.deepcopy(запрос['новые_параметры']), 'архив': переход['архив'],
            'предыдущее': ссылка, 'запечатано': None}}
        сверить_цепочку(вход, новое)
        сверить_перед_переходом()
        писатель.синхронизировать([каталог / 'предыдущее-поколение.json', старый_каталог / 'архив.json'])
        # Файловый fsync поколения 2 не закрепляет его имя в родителе «поколения».
        дескриптор = os.open(каталог.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try: os.fsync(дескриптор)
        finally: os.close(дескриптор)
        писатель.сохранить(путь, новое)
    # Повторный захват того же замка: смена не запускает второй независимый писатель.
    return писатель.переподготовить(вход, запрос['новые_параметры'])


def главная():
    п = argparse.ArgumentParser(description=__doc__)
    п.add_argument('--вход', required=True, type=Path)
    п.add_argument('--смена', required=True, type=Path)
    арг = п.parse_args()
    try:
        итог = сменить_подготовку(канон.разобрать(писатель.прочитать(арг.вход)),
            канон.разобрать(писатель.прочитать(арг.смена)))
        print(писатель.кодировать(итог).decode()); return 0
    except (ValueError, OSError, KeyError, TypeError) as ошибка:
        print(писатель.кодировать({'ошибка': str(ошибка), 'автоматический_повтор': False}).decode(), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(главная())

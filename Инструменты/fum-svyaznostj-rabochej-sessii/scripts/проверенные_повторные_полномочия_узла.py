"""Отдельное историческое чтение A.2; старые эффекты остаются A.1-only."""
import time

import полномочия_ветки_состояния_узла as полномочия
import проверенный_план_журнала_состояния as план
import цели_ветки_состояния_узла as цели

гит = полномочия.гит
канон = план.генератор.читатель.канон
требовать = полномочия.требовать
ПРЕДЕЛ = 1024 * 1024
ПОЛЯ = {'схема', 'ветка', 'хэш_корня', 'начальный_коммит', 'исходный_коммит',
    'путь', 'цели', 'контрольная_ветка', 'план_журнала'} | полномочия.ИДЕНТИЧНОСТЬ


def _ошибки():
    return (канон.приём_делегации.гит.ОшибкаОтчёта, KeyError, TypeError, UnicodeError)


def проверить_порядок(корень, план_коммит, полномочия_коммит):
    """План независим и закреплён строго раньше выбранного A-коммита."""
    try:
        for коммит in (план_коммит, полномочия_коммит): гит.полный_объект(корень, коммит)
        требовать(план_коммит != полномочия_коммит
            and гит.предок(корень, план_коммит, полномочия_коммит),
            'Git-план не является строгим предком полномочий')
    except _ошибки() as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def сверить_проект(данные, *, корень, профиль=None):
    """Проверяем исходные байты предложения; порядок его будущего коммита неизвестен."""
    try:
        начало = time.monotonic_ns(); корень = гит.физический_корень(корень)
        требовать(type(данные) is bytes and 0 < len(данные) <= ПРЕДЕЛ, 'граница A.2 — один МиБ')
        а = полномочия.разобрать(данные); полномочия.поля(а, ПОЛЯ)
        требовать(а['схема'] == 'fum.полномочия-ветки-состояния-узла.2', 'нужна отдельная схема A.2')
        # Повторно используем только структурные проверки. Эта копия не является
        # выбранным Git blob A.1 и никогда не передаётся прежнему публичному API.
        общие = {к: в for к, в in а.items() if к != 'план_журнала'}
        общие['схема'] = полномочия.СХЕМА
        полномочия._сверить_состав(корень, общие, None, новый_эффект=False)
        цели.уникальные(а['цели'])
        проверенный = план.прочитать(а['план_журнала'], корень=корень)
        п = проверенный['документ']
        for имя in полномочия.ИДЕНТИЧНОСТЬ | {'ветка', 'хэш_корня', 'исходный_коммит'}:
            требовать(а[имя] == п[имя], 'A.2 и P.1 расходятся: '+имя)
        требовать(а['начальный_коммит'] == п['первоначальный_запрос']['коммит'],
            'начальная постановка A.2 отличается от истории плана')
        требовать({ф['путь'] for ф in п['файлы']} <= set(а['цели']), 'T не содержит точную пару P.1')
        if профиль is not None:
            профиль.update({'проект_наносекунды': time.monotonic_ns()-начало,
                'API': 0, 'разборов_native': 0})
        return {'документ': а, 'байты': данные, 'sha256': полномочия.хэш(данные),
            'план_журнала': {'источник': а['план_журнала'], 'значение': п},
            'разрешение_установки': False, 'строгий_порядок_Git': False}
    except _ошибки() as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def прочитать(выбор, *, корень, профиль=None):
    """Самостоятельная RO-сверка: полные OID, сырые SHA, P-commit раньше A-commit."""
    try:
        начало = time.monotonic_ns(); корень = гит.физический_корень(корень)
        канон.источник(выбор); гит.полный_объект(корень, выбор['коммит'])
        размер = int(гит.гит(корень, 'cat-file', '-s', выбор['коммит']+':'+выбор['путь']))
        требовать(0 < размер <= ПРЕДЕЛ, 'Git-полномочия превышают границу чтения')
        данные = гит.объект_файла(корень, выбор['коммит'], выбор['путь'])
        требовать(len(данные) <= ПРЕДЕЛ and полномочия.хэш(данные) == выбор['sha256'], 'подмена Git-полномочий')
        итог = сверить_проект(данные, корень=корень, профиль=профиль)
        проверить_порядок(корень, итог['документ']['план_журнала']['коммит'], выбор['коммит'])
        итог['строгий_порядок_Git'] = True
        if профиль is not None: профиль['всего_наносекунды'] = time.monotonic_ns()-начало
        return итог
    except _ошибки() as ошибка:
        raise ValueError(str(ошибка)) from ошибка

"""Конечный выбор закреплённых решений; без записи, API и допуска эффекта."""
import copy
import hashlib
import time

import состояние_задач_узла as читатель

канон = читатель.канон
ПРЕДЕЛ_ЗАДАЧ = 128


def _построить(вход, *, корень, профиль=None):
    """ROOT выбирает источники явно; более поздние решения сами не ищутся."""
    начало = time.monotonic_ns()
    канон.поля(вход, {'схема', 'доверие', 'постановка_выбора', 'решения'})
    канон.требовать(вход['схема'] == 'fum.выбор-ожиданий-узла.1', 'неизвестная схема выбора')
    решения = вход['решения']
    канон.требовать(type(решения) is list and 1 <= len(решения) <= ПРЕДЕЛ_ЗАДАЧ,
        'нужен непустой конечный перечень не более 128 решений')
    корень = читатель.доставка_гит.физический_корень(корень)
    доверие = copy.deepcopy(вход['доверие'])
    замеры = {}
    загрузка = читатель.загрузить_ожидания(доверие, корень=корень, профиль=замеры)
    идентичность = {к: загрузка['ожидания'][к] for к in читатель.ИДЕНТИЧНОСТЬ}
    после_доверия = time.monotonic_ns()
    измерения = {'прочитано_байтов': 0, 'чтений_git_источников': 0}
    канон.прочитать_источник(корень, вход['постановка_выбора'], измерения)
    актёры = []; задачи = set()
    for выбранное in решения:
        решение = канон.разобрать(канон.прочитать_источник(корень, выбранное, измерения))
        канон.решение_координатора(решение)
        канон.требовать(решение['координатор'] == идентичность['координатор'], 'чужое решение ROOT')
        задача = решение['задача']
        канон.требовать(задача != идентичность['координатор'], 'ROOT не входит в дочерний перечень')
        канон.требовать(решение['владелец'] == задача, 'чужой владелец выбранного решения')
        канон.требовать(задача not in задачи, 'повтор выбранной задачи')
        задачи.add(задача)
        актёры.append({'задача': задача, 'хост': решение['хост'], 'владелец': задача,
            'поручение': copy.deepcopy(решение['поручение']),
            'решение_координатора': copy.deepcopy(выбранное),
            'снимок': None, 'доставка': None, 'необязательная_инфраструктура': False})
    после_выбора = time.monotonic_ns()
    кандидат = {'схема': 'fum.ожидаемое-состояние-узла.1', **идентичность,
        'основание': copy.deepcopy(вход['постановка_выбора']), 'предпросмотр': {
            'схема': 'fum.вход-предпросмотра-продолжения.2',
            'координатор': идентичность['координатор'],
            'постановка_выбора': copy.deepcopy(вход['постановка_выбора']),
            'полнота_перечня': False, 'исполнители': актёры}}
    данные = читатель.кодировать(кандидат)
    канон.требовать(len(данные) <= читатель.ПРЕДЕЛ, 'кандидат превышает 64 МиБ')
    # Тот же валидатор источников и ACT, что у установленного expected.
    читатель.проверить_байты_ожиданий(данные, идентичность, корень=корень)
    после_проверки = time.monotonic_ns()
    канон.требовать(читатель.доставка_гит.гит(корень, 'rev-parse', '--verify', доверие['ref'])
        == доверие['источник']['коммит'], 'изменилось доверенное Git-поколение при построении')
    if профиль is not None:
        профиль.update({'доверие_наносекунды': после_доверия - начало,
            'выбор_наносекунды': после_выбора - после_доверия,
            'проверка_наносекунды': после_проверки - после_выбора,
            'повтор_ref_наносекунды': time.monotonic_ns() - после_проверки,
            'всего_наносекунды': time.monotonic_ns() - начало,
            'выбрано_задач': len(актёры), 'кандидат_байты': len(данные),
            'чтение_выбора': измерения, 'чтение_доверия': замеры, 'реальных_API': 0})
    return {'кандидат': данные, 'sha256': hashlib.sha256(данные).hexdigest(),
        'допуск_эффекта': False}


def построить(вход, *, корень, профиль=None):
    try:
        return _построить(вход, корень=корень, профиль=профиль)
    except канон.приём_делегации.гит.ОшибкаОтчёта as ошибка:
        raise ValueError(str(ошибка)) from ошибка

"""Неизменяемое удержание исходных байтов и отдельная компиляция."""
from types import MappingProxyType


class Снимок:
    __slots__ = ("коммит", "пространство", "записи", "байты", "объём_байтов", "чтение_сверка_нс", "компиляция_входа_нс")

    def __init__(сам, коммит, пространство, записи, байты, чтение, компиляция):
        for имя, значение in (("коммит", коммит), ("пространство", пространство),
                ("записи", MappingProxyType(dict(записи))), ("байты", MappingProxyType(dict(байты))),
                ("объём_байтов", sum(map(len, байты.values()))),
                ("чтение_сверка_нс", чтение), ("компиляция_входа_нс", компиляция)):
            object.__setattr__(сам, имя, значение)

    def __setattr__(сам, имя, значение):
        raise AttributeError("снимок неизменяем")

    def скомпилировать(сам):
        return MappingProxyType({имя: compile(данные, f"git:{сам.коммит}:{сам.записи[имя][0]}",
            "exec", dont_inherit=True) for имя, данные in сам.байты.items()})

    def исполнение(сам):
        return Исполнение(сам)

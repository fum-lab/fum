class ОшибкаОбработки(ValueError):
    """Нет доказательства полноты или сохранности обработки."""


def требовать(условие, пояснение):
    if not условие:
        raise ОшибкаОбработки(пояснение)


def объект(значение, поля):
    требовать(type(значение) is dict and set(значение) == set(поля), "неверные поля записи обработки")


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def отпечаток(значение):
    требовать(type(значение) is str and re.fullmatch(r"[0-9a-f]{64}", значение), "неверный SHA-256")


def путь_истории(задача):
    return f"Планирование/задачи/{задача}/обработка-сообщений.jsonl"


def локальный_путь(корень, имя):
    части = гит.точный_путь(имя)
    требовать(not any(часть.startswith(".") for часть in части), "скрытое локальное состояние не является свидетельством")
    путь = корень
    for часть in части:
        if путь.exists():
            требовать(путь.is_dir(), "промежуточный путь не каталог")
            имена = os.listdir(путь)
            требовать(часть in имена or not os.path.lexists(путь / часть), "регистр пути не совпал")
        путь = путь / часть
        требовать(not путь.is_symlink(), "символическая ссылка в каноническом пути")
    return путь


def прочитать_файл(путь):
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
        состояние = os.fstat(поток.fileno())
        требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1, "необычный файл свидетельства")
        байты = поток.read()
        требовать(читатель._метка(состояние) == читатель._метка(os.fstat(поток.fileno())) == читатель._метка(путь.stat()), "файл изменился во время чтения")
        return байты


def проверить_свидетельство(значение, *, команда=False):
    объект(значение, {"путь", "начало", "конец", "sha256"} | ({"формат"} if команда else set()))
    гит.точный_путь(значение["путь"])
    требовать(type(значение["начало"]) is int and type(значение["конец"]) is int and 0 <= значение["начало"] < значение["конец"], "пустой или неверный диапазон свидетельства")
    отпечаток(значение["sha256"])
    if команда:
        требовать(значение["формат"] in {"текст", "части-json"}, "неизвестный формат команды")


def проверить_контекст(контекст):
    объект(контекст, {"граница", "sha256", "экземпляры"})
    требовать(type(контекст["граница"]) is int and контекст["граница"] > 0, "неверная граница контекста")
    отпечаток(контекст["sha256"])
    требовать(type(контекст["экземпляры"]) is list, "нет списка рассмотренных экземпляров")
    for экземпляр in контекст["экземпляры"]:
        отпечаток(экземпляр)
    требовать(len(set(контекст["экземпляры"])) == len(контекст["экземпляры"]), "повторный экземпляр контекста")


def проверить_предложение(запись):
    объект(запись, {"экземпляр", "контекст", "решение", "актуальность", "поздние", "команда", "ответ", "основание"})
    отпечаток(запись["экземпляр"])
    проверить_контекст(запись["контекст"])
    требовать(запись["решение"] in {"ответ", "работа", "уточнение", "отказ"}, "неверное решение")
    требовать(запись["актуальность"] in {"актуально", "уточнено", "заменено", "отменено", "выполнено", "неясно"}, "неверная оценка актуальности")
    требовать(type(запись["поздние"]) is list, "нет списка поздних оснований")
    for экземпляр in запись["поздние"]:
        отпечаток(экземпляр)
    требовать(len(set(запись["поздние"])) == len(запись["поздние"]), "повторное позднее основание")
    требовать(запись["актуальность"] not in {"уточнено", "заменено", "отменено"} or запись["поздние"], "изменение актуальности требует позднего человеческого основания")
    требовать(запись["решение"] != "уточнение" or запись["актуальность"] == "неясно", "открытое уточнение сохраняет неясность")
    for имя in ("команда", "ответ", "основание"):
        проверить_свидетельство(запись[имя], команда=имя == "команда")


def разобрать_историю(байты, задача, источник):
    if not байты:
        return []
    требовать(байты.endswith(b"\n"), "незавершённая история обработки")
    строки = байты.splitlines(keepends=True)
    заголовок = {"схема": "fum.обработка-сообщений.1", "задача": задача, "источник": источник}
    требовать(строки[0] == читатель._байты(заголовок), "неверная идентичность истории обработки")
    результат = []
    последние = {}
    предыдущий = хэш(строки[0])
    граница = 0
    хэш_префикса = hashlib.sha256(строки[0])
    for номер, строка in enumerate(строки[1:], 1):
        событие = читатель._разобрать(строка)
        объект(событие, {"номер", "предыдущий", "основа", "событие", "уточняет", "запись"})
        требовать(читатель._байты(событие) == строка, "неканонические байты истории")
        проверить_предложение(событие["запись"])
        экземпляр = событие["запись"]["экземпляр"]
        требовать(type(событие["номер"]) is int and событие["номер"] == номер and событие["предыдущий"] == предыдущий, "разрыв цепочки обработки")
        требовать(событие["уточняет"] == последние.get(экземпляр), "пересмотр не связан с последней обработкой")
        требовать(событие["основа"] in ({хэш(b""), хэш_префикса.hexdigest()} if номер == 1 else {хэш_префикса.hexdigest()}), "поколение не связано с прежним префиксом")
        тело = {ключ: значение for ключ, значение in событие.items() if ключ != "событие"}
        требовать(событие["событие"] == хэш(читатель._байты(тело)), "изменена запись обработки")
        новая_граница = событие["запись"]["контекст"]["граница"]
        требовать(новая_граница >= граница, "граница рассмотрения откатилась")
        граница = новая_граница
        последние[экземпляр] = событие["событие"]
        предыдущий = хэш(строка)
        хэш_префикса.update(строка)
        результат.append(событие)
    return результат


def _заголовок_истории(байты):
    if not байты:
        return None
    заголовок = читатель._разобрать(байты.split(b"\n", 1)[0])
    требовать(type(заголовок) is dict, "заголовок истории не является объектом")
    return заголовок


def _слияние_гита(корень):
    каталог = Path(os.fsdecode(гит.выполнить_чтение_репозитория(корень, "rev-parse", "--absolute-git-dir").rstrip(b"\n")))
    путь = каталог / "MERGE_HEAD"
    if not os.path.lexists(путь):
        return []
    родители = прочитать_файл(путь).decode("ascii").splitlines()
    требовать(len(родители) == 1, "поддержано слияние ровно двух родителей")
    return [гит.полный_идентификатор(родители[0])]


def _прочитать_объединённую_историю(корень, задача, родители=None):
    вершина = гит.выполнить_чтение_репозитория(корень, "rev-parse", "--verify", "HEAD").decode().strip()
    слияние = _слияние_гита(корень)
    корни = [вершина, *слияние] if родители is None else list(родители)
    требовать(корни and all(гит.полный_идентификатор(э) for э in корни), "нет точных исходных вершин")
    результат = {ключ: {} for ключ in ("родители", "деревья", "состояния", "версии")}
    for коммит in sorted(set(корни)):
        часть = гит.прочитать_историю(корень, путь_истории(задача), коммит)
        for ключ in результат:
            for имя, значение in часть[ключ].items():
                требовать(имя not in результат[ключ] or результат[ключ][имя] == значение, "расхождение исходных Git-снимков")
                результат[ключ][имя] = значение
    требовать(гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip() == вершина
              and _слияние_гита(корень) == слияние, "граница слияния изменилась во время чтения")
    результат.update(вершина=вершина, корни=sorted(set(корни)), слияние=слияние)
    return результат


def _предок(история, предок, потомок, *, включая=False):
    # Для одного импортированного коммита множество потомков проверяется много
    # раз. Запоминаем достижимость по уже пройденным рёбрам, не полагаясь на
    # глубину рекурсии Python при длинной истории.
    кэш = история.setdefault("достижимость_предков", {})
    def содержит(вершина):
        ключ = (предок, вершина)
        if ключ not in кэш:
            стек = [(вершина, False)]
            while стек:
                текущий, готов = стек.pop()
                ключ_текущего = (предок, текущий)
                if ключ_текущего in кэш:
                    continue
                if текущий == предок:
                    кэш[ключ_текущего] = True
                elif готов:
                    кэш[ключ_текущего] = any(кэш[(предок, родитель)]
                        for родитель in история["родители"][текущий])
                else:
                    стек.append((текущий, True))
                    стек.extend((родитель, False) for родитель in история["родители"][текущий]
                        if (предок, родитель) not in кэш)
        return кэш[ключ]
    return содержит(потомок) if включая else any(содержит(родитель)
        for родитель in история["родители"][потомок])


def _вершины_обработок(события):
    последние = {}
    for событие in события.values():
        последние.setdefault(событие["запись"]["экземпляр"], set()).add(событие["событие"])
    for событие in события.values():
        прежние = событие["уточняет"]
        for прежний in (прежние if isinstance(прежние, list) else [прежние] if прежние else []):
            требовать(прежний in события and события[прежний]["запись"]["экземпляр"] == событие["запись"]["экземпляр"], "пересмотр относится к чужой или отсутствующей обработке")
            последние[событие["запись"]["экземпляр"]].discard(прежний)
    return {ключ: sorted(значения) for ключ, значения in последние.items()}


def _покрывает_историю(граф, прежняя):
    return not прежняя or any(байты.startswith(прежняя) for байты in граф["снимки"])


def _разобрать_граф(байты, задача, источник, история, графы, содержащий=None):
    заголовок = _заголовок_истории(байты)
    if not байты or заголовок.get("схема") == "fum.обработка-сообщений.1":
        события = разобрать_историю(байты, задача, источник)
        узлы = {э["событие"]: э for э in события}
        return {"события": узлы, "последние": _вершины_обработок(узлы),
                "снимки": {байты}, "линии": {байты: события}, "заголовок": заголовок}
    объект(заголовок, {"схема", "задача", "источник", "импорты"})
    требовать(заголовок["схема"] == "fum.обработка-сообщений.2" and заголовок["задача"] == задача
              and заголовок["источник"] == источник, "неверная идентичность ветвящейся истории")
    строки = байты.splitlines(keepends=True)
    требовать(байты.endswith(b"\n") and строки[0] == читатель._байты(заголовок), "неканонический заголовок ветвящейся истории")
    импорты = заголовок["импорты"]
    требовать(type(импорты) is list and импорты, "нет исходных историй")
    узлы, снимки, линии = {}, {байты}, {}
    коммиты = []
    for импорт in импорты:
        объект(импорт, {"коммит", "путь", "файловый_объект", "хэш", "байты"})
        коммит = гит.полный_идентификатор(импорт["коммит"])
        гит.полный_идентификатор(импорт["файловый_объект"])
        отпечаток(импорт["хэш"])
        требовать(импорт["путь"] == путь_истории(задача) and type(импорт["байты"]) is int and импорт["байты"] > 0, "неверный путь или размер исходной истории")
        требовать(коммит in история["версии"], "импорт недостижим из проверяемых родителей")
        допустим = _предок(история, коммит, содержащий) if содержащий is not None else any(
            _предок(история, коммит, корень, включая=True) for корень in история["корни"])
        требовать(допустим, "исходная история не является строгим предком версии")
        исходные = история["версии"][коммит]
        состояние = история["состояния"][коммит]
        требовать(состояние is not None and состояние[1] == импорт["файловый_объект"] and исходные is not None
                  and len(исходные) == импорт["байты"] and хэш(исходные) == импорт["хэш"], "исходный Git-снимок истории не совпал")
        требовать(коммит in графы, "циклический либо ещё не проверенный импорт")
        граф = графы[коммит]
        for имя, событие in граф["события"].items():
            требовать(имя not in узлы or узлы[имя] == событие, "одна идентичность обозначает разные события")
            узлы[имя] = событие
        снимки.update(граф["снимки"])
        линии.update(граф["линии"])
        коммиты.append(коммит)
    требовать(коммиты == sorted(set(коммиты)), "неканонический порядок или повтор импорта")
    последние = _вершины_обработок(узлы)
    граница = max((э["запись"]["контекст"]["граница"] for э in узлы.values()), default=0)
    хэш_префикса, предыдущий, местные = hashlib.sha256(строки[0]), хэш(строки[0]), []
    for номер, строка in enumerate(строки[1:], 1):
        событие = читатель._разобрать(строка)
        объект(событие, {"номер", "предыдущий", "основа", "событие", "уточняет", "запись"})
        проверить_предложение(событие["запись"])
        экземпляр = событие["запись"]["экземпляр"]
        требовать(читатель._байты(событие) == строка and type(событие["номер"]) is int and событие["номер"] == номер
                  and событие["предыдущий"] == предыдущий and событие["основа"] == хэш_префикса.hexdigest(), "разрыв локальной цепочки v2")
        требовать(событие["уточняет"] == последние.get(экземпляр, []), "пересмотр не охватывает все конкурирующие обработки")
        тело = {ключ: значение for ключ, значение in событие.items() if ключ != "событие"}
        требовать(событие["событие"] == хэш(читатель._байты(тело)) and событие["событие"] not in узлы, "изменённая либо повторная локальная запись")
        новая_граница = событие["запись"]["контекст"]["граница"]
        требовать(новая_граница >= граница, "граница рассмотрения v2 откатилась")
        граница = новая_граница
        узлы[событие["событие"]] = событие
        последние[экземпляр] = [событие["событие"]]
        местные.append(событие)
        предыдущий = хэш(строка)
        хэш_префикса.update(строка)
    линии[байты] = местные
    return {"события": узлы, "последние": последние, "снимки": снимки, "линии": линии, "заголовок": заголовок}


def _проверить_графы(история, задача, источник):
    графы, активные, версии, рёбра = {}, set(), {}, set()
    for корень in история["корни"]:
        стек = [(корень, False)]
        while стек:
            коммит, завершение = стек.pop()
            if коммит in графы:
                continue
            if not завершение:
                требовать(коммит not in активные, "цикл Git-истории")
                активные.add(коммит)
                стек.append((коммит, True))
                стек.extend((э, False) for э in reversed(история["родители"][коммит]) if э not in графы)
                continue
            байты = история["версии"][коммит] or b""
            if байты not in версии:
                версии[байты] = _разобрать_граф(байты, задача, источник, история, графы, коммит)
            граф = версии[байты]
            заголовок = граф["заголовок"] or {}
            if заголовок.get("схема") == "fum.обработка-сообщений.2":
                заголовочная_строка = байты.split(b"\n", 1)[0]
                родительские = история["родители"][коммит]
                новое_поколение = not any((история["версии"][родитель] or b"").split(b"\n", 1)[0]
                    == заголовочная_строка for родитель in родительские)
                if новое_поколение:
                    требовать(len(родительские) == 2, "новая ветвящаяся история требует merge-коммит")
                    требовать([э["коммит"] for э in заголовок["импорты"]] == sorted(родительские),
                              "импорты не равны точным родителям слияния")
            # Один blob может оказаться в другом DAG-положении: кэш не даёт ancestry.
            for импорт in (граф["заголовок"] or {}).get("импорты", []):
                требовать(_предок(история, импорт["коммит"], коммит),
                          "исходная история не является строгим предком версии")
            for родитель in история["родители"][коммит]:
                ребро = (байты, история["версии"][родитель])
                if ребро not in рёбра:
                    требовать(_покрывает_историю(граф, ребро[1]), "история удалялась или переписывалась в Git")
                    рёбра.add(ребро)
            графы[коммит] = граф
            активные.remove(коммит)
    return графы


def подготовить_слияние_историй(корень_репозитория, задача, родители):
    """Только построение байтов: refs, checkout и исходные события не изменяются."""
    корень = Path(корень_репозитория).resolve(strict=True)
    требовать(type(задача) is str and str(uuid.UUID(задача)) == задача, "неканонический UUID истории")
    требовать(type(родители) is list and len(родители) == 2 and len(set(родители)) == 2,
              "нужны два различных точных исходных коммита")
    история = _прочитать_объединённую_историю(корень, задача, родители)
    исходные = [история["версии"][э] or b"" for э in история["корни"]]
    непустые = [э for э in исходные if э]
    требовать(непустые, "в исходных вершинах нет истории обработки")
    источник = _заголовок_истории(непустые[0])["источник"]
    графы = _проверить_графы(история, задача, источник)
    for коммит in история["корни"]:
        if all(_покрывает_историю(графы[коммит], э) for э in исходные):
            return {"байты": история["версии"][коммит], "событий": len(графы[коммит]["события"]), "изменение_формата": False}
    импорты = [{"коммит": э, "путь": путь_истории(задача), "файловый_объект": история["состояния"][э][1],
                "хэш": хэш(история["версии"][э]), "байты": len(история["версии"][э])}
               for э in история["корни"] if история["версии"][э]]
    байты = читатель._байты({"схема": "fum.обработка-сообщений.2", "задача": задача, "источник": источник, "импорты": импорты})
    граф = _разобрать_граф(байты, задача, источник, история, графы)
    требовать(all(_покрывает_историю(граф, э) for э in исходные), "результат не сохраняет обоих родителей")
    return {"байты": байты, "событий": len(граф["события"]), "изменение_формата": True}


def сверить_границы(источник, контексты, *, кэш=None, без_записи=False):
    ожидания = {}
    for контекст in контексты:
        граница = контекст["граница"]
        требовать(граница not in ожидания or ожидания[граница] == контекст["sha256"], "противоречащие границы контекста")
        ожидания[граница] = контекст["sha256"]
    if not ожидания:
        return {"прочитано_байтов": 0, "режим": "нет сохранённых границ"}
    if кэш is not None:
        путь = читатель._путь(кэш)
        требовать(not any(os.path.lexists(предок / ".git") for предок in путь.parents), "кэш границ запрещён в Git checkout")
        with nullcontext() if без_записи else читатель._замок(путь):
            прежние = None
            if путь.exists():
                читатель._обычный(путь.stat(), приватный=True)
                оболочка = читатель._разобрать(прочитать_файл(путь))
                объект(оболочка, {"данные", "sha256"})
                прежние = оболочка["данные"]
                требовать(хэш(читатель._байты(прежние)) == оболочка["sha256"], "кэш границ повреждён")
                объект(прежние, {"схема", "метка", "реализация", "границы"})
                требовать(прежние["схема"] == "fum.кэш-границ-сообщений.1" and type(прежние["границы"]) is dict, "неверная схема кэша границ")
                требовать(type(прежние["метка"]) is list and len(прежние["метка"]) == 5 and all(type(э) is int for э in прежние["метка"]), "повреждена метка источника")
                отпечаток(прежние["реализация"])
                for ключ, значение in прежние["границы"].items():
                    требовать(type(ключ) is str and re.fullmatch(r"[1-9][0-9]*", ключ), "неверная сохранённая граница")
                    отпечаток(значение)
            состояние = Path(источник).stat()
            метка = читатель._метка(состояние)
            читатель._обычный(состояние)
            совпало = прежние is not None and прежние["метка"] == метка and прежние["реализация"] == _РЕАЛИЗАЦИЯ
            сохранённые = прежние["границы"] if совпало else {}
            for граница, ожидаемый in ожидания.items():
                требовать(str(граница) not in сохранённые or сохранённые[str(граница)] == ожидаемый, "противоречащая ранее проверенная граница")
            if all(str(граница) in сохранённые for граница in ожидания) and читатель._метка(Path(источник).stat()) == метка:
                return {"прочитано_байтов": 0, "режим": "неизменная метка ФС"}
            профиль = сверить_границы(источник, контексты)
            if без_записи or читатель._метка(Path(источник).stat()) != метка:
                # Проверенные префиксы пригодны; метка нового хвоста к ним не относится.
                профиль["кэш_сохранён"] = False
                return профиль
            данные = {"схема": "fum.кэш-границ-сообщений.1", "метка": метка, "реализация": _РЕАЛИЗАЦИЯ,
                      "границы": {**сохранённые, **{str(ключ): значение for ключ, значение in ожидания.items()}}}
            читатель._установить(путь, читатель._байты({"данные": данные, "sha256": хэш(читатель._байты(данные))}))
            return профиль
    with os.fdopen(os.open(источник, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
        состояние = os.fstat(поток.fileno())
        читатель._обычный(состояние)
        требовать(max(ожидания) <= состояние.st_size, "источник короче рассмотренной границы")
        хэширование = hashlib.sha256()
        прочитано = 0
        последний = b""
        for граница in sorted(ожидания):
            while прочитано < граница:
                блок = поток.read(min(1024 * 1024, граница - прочитано))
                требовать(bool(блок), "источник короче рассмотренной границы")
                хэширование.update(блок)
                прочитано += len(блок)
                последний = блок[-1:]
            требовать(последний == b"\n" and хэширование.hexdigest() == ожидания[граница], "изменён рассмотренный контекст")
        дописано, перепроверено = читатель._сверить_снимок(поток, Path(источник), состояние,
            {"граница": max(ожидания), "sha256": ожидания[max(ожидания)]})
        return {"прочитано_байтов": прочитано + перепроверено, "режим": "проверены байты префикса",
                "дописано_при_сверке": дописано}


def контекст_снимка(снимок):
    return {"граница": снимок["граница"], "sha256": снимок["sha256"], "экземпляры": [э["экземпляр"] for э in снимок["сообщения"]]}


def сверить_экземпляры(запись, снимок):
    контекст = запись["контекст"]
    сообщения = {э["экземпляр"]: э for э in снимок["сообщения"]}
    ожидаемые = [э["экземпляр"] for э in снимок["сообщения"] if э["позиция"]["конец"] <= контекст["граница"]]
    требовать(контекст["граница"] <= снимок["граница"] and контекст["экземпляры"] == ожидаемые, "рассмотренный контекст пропускает исходные экземпляры")
    требовать(запись["экземпляр"] in ожидаемые, "чужой или нерассмотренный экземпляр")
    исходное = сообщения[запись["экземпляр"]]
    требовать(исходное["происхождение"] == "человек", "происхождение команды не подтверждено")
    for ссылка in запись["поздние"]:
        требовать(ссылка in ожидаемые and сообщения[ссылка]["происхождение"] == "человек" and сообщения[ссылка]["позиция"]["начало"] > исходное["позиция"]["начало"], "основание не является поздним человеческим сообщением")
    return исходное


def фрагмент(свидетельство, байты):
    требовать(байты is not None and свидетельство["конец"] <= len(байты), "свидетельство отсутствует или усечено")
    часть = байты[свидетельство["начало"]:свидетельство["конец"]]
    текст = часть.decode("utf-8")
    требовать(текст.strip() and "<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->" not in текст and хэш(часть) == свидетельство["sha256"], "свидетельство изменено или пусто")
    return часть


def сверить_свидетельства(запись, исходное, прочитать):
    команда = запись["команда"]
    сохранённое = фрагмент(команда, прочитать(команда["путь"]))
    содержимое = исходное["содержимое"]
    if команда["формат"] == "текст":
        требовать(type(содержимое) is list and содержимое and all(type(часть) is dict and set(часть) == {"type", "text"} and часть["type"] == "input_text" and type(часть["text"]) is str for часть in содержимое), "текстовая копия теряет часть сообщения")
        ожидаемое = "".join(часть["text"] for часть in содержимое).encode("utf-8")
    else:
        ожидаемое = читатель._байты(содержимое)
    требовать(сохранённое == ожидаемое, "сохранена не полная исходная команда")
    for имя in ("ответ", "основание"):
        фрагмент(запись[имя], прочитать(запись[имя]["путь"]))


def загрузить(источник, задача, корень, кэш, перепроверить, кэшировать_границы=True, без_записи=False, чтение=None):
    начало = time.perf_counter_ns()
    снимок = чтение() if чтение is not None else читатель.прочитать_сообщения(источник, задача, корень_репозитория=корень, кэш=кэш, перепроверить=перепроверить, без_записи=без_записи)
    время_источника = time.perf_counter_ns() - начало
    начало_истории = time.perf_counter_ns()
    путь = локальный_путь(корень, путь_истории(задача))
    история = _прочитать_объединённую_историю(корень, задача)
    сырые = прочитать_файл(путь) if путь.exists() else b""
    графы = _проверить_графы(история, задача, снимок["источник"])
    заголовок = _заголовок_истории(сырые)
    версия_HEAD = история["версии"][история["вершина"]] or b""
    if заголовок is not None and заголовок.get("схема") == "fum.обработка-сообщений.2":
        прежний_заголовок = версия_HEAD.split(b"\n", 1)[0]
        новый_заголовок = сырые.split(b"\n", 1)[0]
        if новый_заголовок != прежний_заголовок:
            требовать(len(история["слияние"]) == 1, "новая ветвящаяся история требует начатого слияния")
            требовать([э["коммит"] for э in заголовок["импорты"]] == история["корни"],
                      "импорты не равны точным родителям текущего слияния")
    граф = _разобрать_граф(сырые, задача, снимок["источник"], история, графы)
    требовать(all(_покрывает_историю(граф, история["версии"][э]) for э in история["корни"]), "история удалена или переписана в checkout")
    события = list(граф["события"].values())
    контексты = [событие["запись"]["контекст"] for событие in события]
    время_истории = time.perf_counter_ns() - начало_истории
    начало_границ = time.perf_counter_ns()
    путь_кэша = читатель._путь(кэш).with_name(Path(кэш).name + ".границы") if кэш is not None and кэшировать_границы and not перепроверить else None
    профиль_границ = сверить_границы(источник, контексты, кэш=путь_кэша, без_записи=без_записи)
    профиль_границ["длительность_наносекунды"] = time.perf_counter_ns() - начало_границ
    for событие in события:
        сверить_экземпляры(событие["запись"], снимок)
    история["графы"] = графы
    история["текущий_граф"] = граф
    история["разобранные_версии"] = {коммит: list(значение["события"].values()) for коммит, значение in графы.items()}
    return снимок, сырые, события, история, {"чтение_диалога": время_источника, "история_гита": время_истории, "границы_контекста": профиль_границ}


def вычислить_остаток(снимок, сырые, события, история, корень, профиль):
    начало = time.perf_counter_ns()
    граф = история["текущий_граф"]
    кэш_файлов = {}
    кэш_версий = {}
    def читать(имя):
        if имя not in кэш_файлов:
            кэш_файлов[имя] = прочитать_файл(локальный_путь(корень, имя))
        return кэш_файлов[имя]
    def версии(имя):
        if имя not in кэш_версий:
            состояния = гит.состояния_пути(корень, история["деревья"], имя)
            объекты = гит.прочитать_объекты(корень, [э[1] for э in состояния.values() if э is not None], "blob")
            кэш_версий[имя] = {коммит: None if э is None else объекты[э[1]] for коммит, э in состояния.items()}
        return кэш_версий[имя]
    остаток = []
    for сообщение in снимок["сообщения"]:
        экземпляр = сообщение["экземпляр"]
        вершины = граф["последние"].get(экземпляр, [])
        событие = граф["события"][вершины[0]] if len(вершины) == 1 else None
        причины = []
        поздние = []
        if событие is None:
            причины.append("конкурирующие обработки: " + ", ".join(вершины) if вершины else "нет записи обработки")
            поздние = [э["экземпляр"] for э in снимок["сообщения"] if э["позиция"]["начало"] > сообщение["позиция"]["начало"]]
        else:
            запись = событие["запись"]
            try:
                сверить_свидетельства(запись, сообщение, читать)
                # Возврат удалённого свидетельства не стирает разрыв в Git.
                for коммит, прежние in история["разобранные_версии"].items():
                    if any(э["событие"] == событие["событие"] for э in прежние):
                        сверить_свидетельства(запись, сообщение, lambda имя: версии(имя)[коммит])
            except (ОшибкаОбработки, гит.ОшибкаОтчёта, OSError, UnicodeError) as ошибка:
                причины.append("свидетельство недействительно: " + str(ошибка))
            поздние = [э["экземпляр"] for э in снимок["сообщения"] if э["позиция"]["начало"] >= запись["контекст"]["граница"]]
            if поздние:
                причины.append("новый поздний ввод")
            if запись["актуальность"] == "неясно":
                причины.append("актуальность неясна")
        if сообщение["происхождение"] != "человек":
            причины.append("происхождение не подтверждено")
        if причины:
            остаток.append({"экземпляр": экземпляр, "причины": причины, "поздние": поздние,
                           "последняя_обработка": None if событие is None else событие["событие"]})
    профиль["свидетельства_и_остаток"] = time.perf_counter_ns() - начало
    return {"схема": "fum.остаток-сообщений.1", "задача": снимок["задача"], "источник": снимок["источник"],
            "контекст": контекст_снимка(снимок), "история_sha256": хэш(сырые), "сообщения": снимок["сообщения"],
            "остаток": остаток, "полнота_источника": снимок["полнота_подтверждена"], "неполный_хвост": снимок["неполный_хвост"],
            "разбор_сообщений_завершён": снимок["полнота_подтверждена"] and not остаток,
            "завершение_задачи_доказано": False, "профиль": профиль}, кэш_файлов


def получить_остаток(источник, задача, *, корень_репозитория, кэш=None, перепроверить=False, кэшировать_границы=True, без_записи=False, чтение=None):
    начало = time.perf_counter_ns()
    try:
        корень = Path(корень_репозитория).resolve(strict=True)
        if чтение is None:
            чтение = читатель._сеанс_чтения(источник, задача, корень_репозитория=корень,
                кэш=кэш, перепроверить=перепроверить, без_записи=без_записи)
        требовать(type(чтение) is читатель._СеансЧтения and чтение.соответствует(источник, задача,
            корень_репозитория=корень, кэш=кэш, перепроверить=перепроверить, без_записи=без_записи),
            "сеанс чтения не соответствует источнику или режиму")
        снимок, сырые, события, история, профиль = загрузить(источник, задача, корень, кэш, перепроверить, кэшировать_границы, без_записи, чтение)
        результат, свидетельства = вычислить_остаток(снимок, сырые, события, история, корень, профиль)
        начало_сверки = time.perf_counter_ns()
        свежий = чтение()
        требовать(контекст_снимка(свежий)["экземпляры"] == контекст_снимка(снимок)["экземпляры"] and свежий["полнота_подтверждена"] == снимок["полнота_подтверждена"], "источник изменился во время вычисления остатка")
        путь = локальный_путь(корень, путь_истории(задача))
        требовать((прочитать_файл(путь) if путь.exists() else b"") == сырые, "история изменилась во время вычисления остатка")
        for имя, байты in свидетельства.items():
            требовать(прочитать_файл(локальный_путь(корень, имя)) == байты, "свидетельство изменилось перед выдачей остатка")
        требовать(гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip() == история["вершина"], "HEAD изменился во время проверки")
        требовать(_слияние_гита(корень) == история["слияние"], "граница слияния изменилась перед выдачей остатка")
        результат["непроверенный_хвост"] = свежий["неполный_хвост"] + свежий["дописано_после_снимка"]
        результат["граница_заключительной_сверки"] = свежий["граница"]
        результат["полнота_источника"] = свежий["полнота_подтверждена"] and результат["непроверенный_хвост"] == 0
        результат["разбор_сообщений_завершён"] = результат["полнота_источника"] and not результат["остаток"]
        результат["профиль"]["заключительная_сверка"] = time.perf_counter_ns() - начало_сверки
        результат["профиль"]["длительность_наносекунды"] = time.perf_counter_ns() - начало
        return результат
    except (OSError, ValueError, TypeError, KeyError, UnicodeError, гит.ОшибкаОтчёта) as ошибка:
        if isinstance(ошибка, ОшибкаОбработки):
            raise
        raise ОшибкаОбработки("источник, история или свидетельства недоступны либо повреждены") from ошибка


def сохранить_обработку(источник, задача, *, корень_репозитория, кэш, запись, ожидаемая_история):
    try:
        корень = Path(корень_репозитория).resolve(strict=True)
        проверить_предложение(запись)
        отпечаток(ожидаемая_история)
        # Читатель проверяет приватную границу до создания отдельного замка.
        читатель.прочитать_сообщения(источник, задача, корень_репозитория=корень, кэш=кэш)
        каталог_гита = Path(os.fsdecode(гит.выполнить_чтение_репозитория(корень, "rev-parse", "--absolute-git-dir").rstrip(b"\n"))).resolve(strict=True)
        # Один физический checkout и UUID имеют один замок при любых кэшах.
        with читатель._замок(каталог_гита / ("fum-обработка-" + задача)):
            снимок, сырые, события, история, профиль = загрузить(источник, задача, корень, кэш, False)
            повтор = None
            for линейные, местные in история["текущий_граф"]["линии"].items():
                хэш_префикса = hashlib.sha256(линейные.splitlines(keepends=True)[0] if линейные else b"")
                for событие in местные:
                    хэш_префикса.update(читатель._байты(событие))
                    if событие["основа"] == ожидаемая_история and событие["запись"] == запись:
                        найденный = (событие["событие"], хэш_префикса.hexdigest())
                        требовать(повтор is None or повтор == найденный, "неоднозначный повтор обработки")
                        повтор = найденный
            if повтор is not None:
                # Повтор той же операции после replace не создаёт новое решение.
                исходное = сверить_экземпляры(запись, снимок)
                сверить_свидетельства(запись, исходное, lambda имя: прочитать_файл(локальный_путь(корень, имя)))
                путь = локальный_путь(корень, путь_истории(задача))
                with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
                    os.fsync(поток.fileno())
                синхронизировать_каталог(путь.parent)
                требовать(прочитать_файл(путь) == сырые, "история изменилась перед квитанцией повтора")
                требовать(гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip() == история["вершина"],
                          "HEAD изменился перед квитанцией повтора")
                требовать(_слияние_гита(корень) == история["слияние"], "граница слияния изменилась перед квитанцией повтора")
                return {"событие": повтор[0], "история_sha256": повтор[1], "завершение_задачи_доказано": False}
            требовать(хэш(сырые) == ожидаемая_история, "поколение истории уже изменилось")
            требовать(снимок["полнота_подтверждена"], "неполный или неоднозначный источник")
            исходное = сверить_экземпляры(запись, снимок)
            требовать(запись["контекст"]["экземпляры"] == контекст_снимка(снимок)["экземпляры"], "после рассмотрения появился новый ввод")
            сверить_границы(источник, [запись["контекст"]])
            сверить_свидетельства(запись, исходное, lambda имя: прочитать_файл(локальный_путь(корень, имя)))
            граф = история["текущий_граф"]
            if not сырые:
                сырые = читатель._байты({"схема": "fum.обработка-сообщений.1", "задача": задача, "источник": снимок["источник"]})
            ветвление = _заголовок_истории(сырые)["схема"] == "fum.обработка-сообщений.2"
            последние = граф["последние"].get(запись["экземпляр"], [])
            событие = {"номер": len(сырые.splitlines()) if ветвление else len(события) + 1,
                       "предыдущий": хэш(сырые.splitlines(keepends=True)[-1]), "основа": ожидаемая_история,
                       "уточняет": последние if ветвление else последние[0] if последние else None, "запись": copy.deepcopy(запись)}
            событие["событие"] = хэш(читатель._байты(событие))
            новые = сырые + читатель._байты(событие)
            _разобрать_граф(новые, задача, снимок["источник"], история, история["графы"])
            свежий = читатель.прочитать_сообщения(источник, задача, корень_репозитория=корень, кэш=кэш)
            требовать(свежий["полнота_подтверждена"] and свежий["дописано_после_снимка"] == 0 and контекст_снимка(свежий)["экземпляры"] == запись["контекст"]["экземпляры"], "источник изменился перед записью обработки")
            требовать(гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip() == история["вершина"], "HEAD изменился перед записью")
            требовать(_слияние_гита(корень) == история["слияние"], "граница слияния изменилась перед записью")
            путь = локальный_путь(корень, путь_истории(задача))
            фактические = прочитать_файл(путь) if путь.exists() else b""
            требовать(хэш(фактические) == ожидаемая_история, "история изменилась перед записью")
            сверить_свидетельства(запись, исходное, lambda имя: прочитать_файл(локальный_путь(корень, имя)))
            каталог = корень
            for часть in путь.parent.relative_to(корень).parts:
                следующий = каталог / часть
                if not следующий.exists():
                    следующий.mkdir()
                требовать(следующий.is_dir() and not следующий.is_symlink(), "каталог истории подменён")
                # Повтор после mkdir и отказа fsync не знает, какой предок уже долговечен.
                синхронизировать_каталог(каталог)
                каталог = следующий
            читатель._установить(путь, новые)
            return {"событие": событие["событие"], "история_sha256": хэш(новые), "завершение_задачи_доказано": False}
    except (OSError, ValueError, TypeError, KeyError, UnicodeError, гит.ОшибкаОтчёта) as ошибка:
        if isinstance(ошибка, ОшибкаОбработки):
            raise
        raise ОшибкаОбработки("обработка не подтверждена: запись или её входы повреждены") from ошибка


def сохранить_обработку_пакет(источник, задача, *, корень_репозитория, кэш, записи, ожидаемая_история):
    """Атомарно применить несколько решений к одному проверенному снимку.

    Пакет сохраняет ту же границу одного писателя и тот же контроль источника,
    что и одиночная запись, но не перечитывает большой JSONL для каждого
    сообщения. Это устраняет повторную дорогую работу при разборе позднего
    остатка, не ослабляя проверку свидетельств и поколения истории.
    """
    try:
        требовать(isinstance(записи, list) and записи, "пустой пакет обработки")
        for запись in записи:
            проверить_предложение(запись)
        требовать(len({э["экземпляр"] for э in записи}) == len(записи), "повторный экземпляр в пакете")
        требовать(all(э["контекст"] == записи[0]["контекст"] for э in записи), "пакет использует разные контексты")
        корень = Path(корень_репозитория).resolve(strict=True)
        отпечаток(ожидаемая_история)
        читатель.прочитать_сообщения(источник, задача, корень_репозитория=корень, кэш=кэш)
        каталог_гита = Path(os.fsdecode(гит.выполнить_чтение_репозитория(
            корень, "rev-parse", "--absolute-git-dir").rstrip(b"\n"))).resolve(strict=True)
        with читатель._замок(каталог_гита / ("fum-обработка-" + задача)):
            снимок, сырые, события, история, профиль = загрузить(источник, задача, корень, кэш, False)
            требовать(снимок["полнота_подтверждена"], "неполный или неоднозначный источник")
            контекст = контекст_снимка(снимок)
            граф = история["текущий_граф"]
            последние = copy.deepcopy(граф["последние"])
            текущая_история = хэш(сырые)
            if текущая_история != ожидаемая_история:
                # Ответ CLI мог быть потерян после атомарной установки. Как
                # и одиночный путь, распознаём ровно уже установленную
                # непрерывную последовательность и не создаём её второй раз.
                длина = len(записи)
                последовательности = (линия[начало:начало + длина]
                    for линия in граф["линии"].values()
                    for начало in range(max(0, len(линия) - длина + 1)))
                for кандидат in последовательности:
                    if len(кандидат) != длина or кандидат[0]["основа"] != ожидаемая_история:
                        continue
                    if not all(событие["запись"] == запись
                               for событие, запись in zip(кандидат, записи, strict=True)):
                        continue
                    сверить_границы(источник, [записи[0]["контекст"]])
                    for запись in записи:
                        исходное = сверить_экземпляры(запись, снимок)
                        сверить_свидетельства(запись, исходное,
                            lambda имя: прочитать_файл(локальный_путь(корень, имя)))
                    путь = локальный_путь(корень, путь_истории(задача))
                    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
                        os.fsync(поток.fileno())
                    синхронизировать_каталог(путь.parent)
                    требовать(прочитать_файл(путь) == сырые, "история изменилась перед квитанцией пакета")
                    требовать(гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip()
                        == история["вершина"], "HEAD изменился перед квитанцией пакета")
                    требовать(_слияние_гита(корень) == история["слияние"],
                        "граница слияния изменилась перед квитанцией пакета")
                    return {"события": [событие["событие"] for событие in кандидат],
                        "история_sha256": текущая_история, "количество": длина,
                        "завершение_задачи_доказано": False}
                требовать(False, "поколение истории уже изменилось")
            новые = сырые
            if not новые:
                новые = читатель._байты({"схема": "fum.обработка-сообщений.1",
                    "задача": задача, "источник": снимок["источник"]})
            ветвление = _заголовок_истории(новые)["схема"] == "fum.обработка-сообщений.2"
            новые_события = []
            номер = len(новые.splitlines())
            предыдущий = хэш(новые.splitlines(keepends=True)[-1])
            хэш_новых = hashlib.sha256(новые)
            буфер = bytearray(новые)
            сверить_границы(источник, [записи[0]["контекст"]])
            for запись in записи:
                экземпляр = запись["экземпляр"]
                требовать(запись["контекст"] == контекст, "пакет использует устаревший контекст")
                исходное = сверить_экземпляры(запись, снимок)
                сверить_свидетельства(запись, исходное,
                    lambda имя: прочитать_файл(локальный_путь(корень, имя)))
                прежние = последние.get(экземпляр, [])
                событие = {"номер": номер, "предыдущий": предыдущий,
                    "основа": хэш_новых.hexdigest() if новые_события else ожидаемая_история,
                    "уточняет": прежние if ветвление else прежние[0] if прежние else None,
                    "запись": copy.deepcopy(запись)}
                событие["событие"] = хэш(читатель._байты(событие))
                строка = читатель._байты(событие)
                буфер.extend(строка)
                хэш_новых.update(строка)
                номер, предыдущий = номер + 1, хэш(строка)
                последние[экземпляр] = [событие["событие"]]
                новые_события.append(событие)
            новые = bytes(буфер)
            _разобрать_граф(новые, задача, снимок["источник"], история, история["графы"])
            свежий = читатель.прочитать_сообщения(источник, задача, корень_репозитория=корень, кэш=кэш)
            требовать(свежий["полнота_подтверждена"] and свежий["дописано_после_снимка"] == 0
                and контекст_снимка(свежий)["экземпляры"] == контекст["экземпляры"],
                "источник изменился перед записью обработки")
            требовать(гит.выполнить_чтение_репозитория(корень, "rev-parse", "HEAD").decode().strip()
                == история["вершина"], "HEAD изменился перед записью")
            требовать(_слияние_гита(корень) == история["слияние"], "граница слияния изменилась перед записью")
            путь = локальный_путь(корень, путь_истории(задача))
            фактические = прочитать_файл(путь) if путь.exists() else b""
            требовать(хэш(фактические) == ожидаемая_история, "история изменилась перед записью")
            for запись in записи:
                сверить_свидетельства(запись, сверить_экземпляры(запись, снимок),
                    lambda имя: прочитать_файл(локальный_путь(корень, имя)))
            каталог = корень
            for часть in путь.parent.relative_to(корень).parts:
                следующий = каталог / часть
                if not следующий.exists():
                    следующий.mkdir()
                требовать(следующий.is_dir() and not следующий.is_symlink(), "каталог истории подменён")
                синхронизировать_каталог(каталог)
                каталог = следующий
            читатель._установить(путь, новые)
            return {"события": [э["событие"] for э in новые_события],
                "история_sha256": хэш(новые), "количество": len(записи),
                "завершение_задачи_доказано": False}
    except (OSError, ValueError, TypeError, KeyError, UnicodeError, гит.ОшибкаОтчёта) as ошибка:
        if isinstance(ошибка, ОшибкаОбработки):
            raise
        raise ОшибкаОбработки("пакетная обработка не подтверждена: запись или её входы повреждены") from ошибка


def синхронизировать_каталог(путь):
    дескриптор = os.open(путь, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)

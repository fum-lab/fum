"""Отдельная связь U.3/N.4 с неизменяемыми R/P.2 и новой базой H.

Модуль не активирует узел и не формирует полный expected: он проверяет
конечный лабораторный эффект через уже существующий писатель.
"""
from pathlib import Path
import re

import обычное_поручение as обычное
import полномочия_повторного_состояния_узла as полномочия
import проверенный_повторный_план_состояния as планы
import журнал_повторного_состояния_узла as журнал

требовать = полномочия.требовать


def проверить_базу(корень, вход, параметры, назначение):
    """R может предшествовать H; прежние expected-байты обязаны совпасть."""
    требовать(вход['схема'] == 'fum.обновление-ожиданий-узла.3'
        and назначение['схема'] == 'fum.назначение-писателя-ожиданий.4'
        and параметры['схема'] == 'fum.создание-коммита.11', 'смешаны версии повторного эффекта')
    документ = полномочия.прочитать(корень, вход['полномочия_узла'])['документ']
    план = планы.прочитать(документ['план_журнала'], корень=корень)['документ']
    требовать(вход['доверие'] == план['доверие'] and вход['первое_создание'] is None,
        'U.3 требует точное прежнее доверие P.2')
    требовать(вход['путь'] == документ['путь'] and параметры['исходный_коммит'] ==
        документ['исходный_коммит'] == план['исходный_коммит'], 'подменены expected или H повторного эффекта')
    прежние = полномочия.прежние.ИДЕНТИЧНОСТЬ
    требовать(all(назначение[ключ] == документ[ключ] for ключ in прежние), 'N.4 расходится с A.3')
    требовать(all(план['доверие'][ключ] == документ[ключ]
        for ключ in прежние - {'поколение_полномочий'})
        and план['доверие']['поколение_полномочий'] != документ['поколение_полномочий'],
        'утрачена связь старого и нового поколения')
    исходник = план['доверие']['источник']
    данные = полномочия.гит.объект_файла(корень, исходник['коммит'], исходник['путь'])
    требовать(полномочия.прежние.хэш(данные) == исходник['sha256']
        and полномочия.гит.предок(корень, исходник['коммит'], план['исходный_коммит'])
        and данные == полномочия.гит.объект_файла(корень, план['исходный_коммит'], исходник['путь']),
        'expected в R и H различается либо R не предшествует H')
    журнал.проверить_установку(параметры, доверенное_поручение=вход['акт'])
    return данные, план['исходный_коммит']


def проверить_историческую_подготовку(корень, независимый_акт, параметры, подготовка):
    """Исторические Git и квитанция; native, рабочая пара и READY не читаются."""
    требовать(параметры['схема'] == 'fum.создание-коммита.11'
        and подготовка['схема'] == 'fum.подготовленный-коммит.13'
        and подготовка['параметры'] == параметры, 'смешана историческая повторная подготовка')
    акт = обычное.прочитать_акт(корень, независимый_акт, новый_эффект=False)
    документ = полномочия.проверить_дерево(корень, параметры['исполнитель'], параметры['ветка'],
        акт['полномочия_узла'], исходный_коммит=параметры['исходный_коммит'],
        цели=параметры['разрешённые_цели'], новый_эффект=False)
    план = планы.прочитать(документ['план_журнала'], корень=корень)['документ']
    требовать(параметры['корень'] == str(корень) and параметры['ветка'] == документ['ветка']
        and параметры['исполнитель'] == документ['владелец'] == акт['исполнитель']
        and параметры['задача'] == акт['координатор']
        and параметры['выбранное_поручение'] == независимый_акт
        and параметры['родители'] == [документ['исходный_коммит']]
        and параметры['запрос'] == план['файлы'][0]['путь']
        and параметры['история_модели'] in документ['цели']
        and подготовка['команды'] == план['команды']
        and [{к: в for к, в in и.items() if к not in {'путь', 'кэш'}}
            for и in параметры['источники']] == план['источники_команд'],
        'историческая подготовка расходится с ACT/A/P.2')
    привязка = подготовка['привязка_поручения']
    полномочия.прежние.поля(привязка, {'выбранное_поручение', 'полномочия_узла',
        'нативное_начало', 'нативное_поручение'})
    требовать(привязка['выбранное_поручение'] == независимый_акт
        and привязка['полномочия_узла'] == {'источник': акт['полномочия_узла'], 'значение': документ},
        'подменена сохранённая независимая привязка')
    for имя in ('нативное_начало', 'нативное_поручение'):
        префикс = привязка[имя]
        полномочия.прежние.поля(префикс, {'граница', 'sha256'})
        требовать(type(префикс['граница']) is int and 0 < префикс['граница'] <= 16 * 1024 * 1024
            and type(префикс['sha256']) is str and re.fullmatch('[0-9a-f]{64}', префикс['sha256']),
            'повреждено историческое наблюдение native')
    требовать(привязка['нативное_начало']['граница'] <= привязка['нативное_поручение']['граница'],
        'переставлены исторические native-префиксы')
    цепь = {'схема': журнал.СХЕМА, 'корень': str(корень), 'ветка': параметры['ветка'],
        'владелец': параметры['исполнитель'], 'исходный_коммит': параметры['исходный_коммит'],
        'контрольная_ветка': документ['контрольная_ветка'], 'акт': независимый_акт,
        'полномочия': акт['полномочия_узла'], 'план': документ['план_журнала'],
        'этап': план['идентификатор'], 'цели': параметры['разрешённые_цели']}
    повтор = подготовка['привязка_повтора']
    полномочия.прежние.поля(повтор, {'схема', 'цепь', 'квитанция', 'документ'})
    требовать(повтор['схема'] == 'fum.привязка-повторного-журнала.1' and повтор['цепь'] == цепь,
        'чужая историческая цепь повторного Журнала')
    квитанция = повтор['документ']
    полномочия.прежние.поля(квитанция, {'схема', 'привязка', 'папка', 'файлы'})
    требовать(квитанция['схема'] == 'fum.квитанция-повторного-журнала.1'
        and квитанция['привязка'] == цепь and type(квитанция['файлы']) is list
        and len(квитанция['файлы']) == 2, 'подменён исторический документ установки')
    def метка(значение):
        полномочия.прежние.поля(значение, {'устройство', 'номер_файла'})
        требовать(all(type(в) is int and в >= 0 for в in значение.values()), 'неверная историческая метка')
    метка(квитанция['папка'])
    for файл, ожидаемый in zip(квитанция['файлы'], план['файлы'], strict=True):
        полномочия.прежние.поля(файл, {'путь', 'sha256', 'режим', 'устройство', 'номер_файла'})
        требовать(all(файл[к] == ожидаемый[к] for к in ('путь', 'sha256', 'режим')),
            'исторические исходные байты пары не совпадают с P.2')
        метка({к: файл[к] for к in ('устройство', 'номер_файла')})
    каталог = журнал._каталог(параметры, корень)
    ссылка = {'путь': str(каталог / 'квитанция.json'), 'sha256': журнал.контракт.хэш(журнал.байты(квитанция))}
    требовать(повтор['квитанция'] == ссылка
        and журнал._прочитать(каталог / 'квитанция.json', приватный=True)[0] == журнал.байты(квитанция),
        'утрачена или изменена историческая квитанция установки')
    журнал._проверить_эпизод(корень, план, цепь, каталог)
    return документ

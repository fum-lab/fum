"""Представить страницу сохранённого остатка без изменения обработки."""
import hashlib
import json
from collections import Counter


МАКСИМУМ_БАЙТОВ_ЖИВОЙ_СТРАНИЦЫ = 64 * 1024 * 1024
МАКСИМУМ_БАЙТОВ_КОМАНДЫ = 64 * 1024
МАКСИМУМ_БАЙТОВ_ДЕСКРИПТОРА = 64 * 1024


def требовать(условие, сообщение):
    if not условие:
        raise ValueError(сообщение)


def объект(пары):
    результат = {}
    for ключ, значение in пары:
        требовать(ключ not in результат, "повтор поля JSON")
        результат[ключ] = значение
    return результат


def закодировать(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True,
        separators=(",", ":"), allow_nan=False) + "\n").encode("utf-8")


def проверить(значение):
    требовать(isinstance(значение, dict) and значение.get("схема") == "fum.остаток-сообщений.1",
        "неизвестная схема полного результата")
    сообщения, остаток = значение["сообщения"], значение["остаток"]
    требовать(isinstance(сообщения, list) and isinstance(остаток, list), "ожидались массивы остатка и сообщений")
    экземпляры = []
    for сообщение in сообщения:
        требовать(isinstance(сообщение, dict), "повреждённое сообщение")
        экземпляр = сообщение["экземпляр"]
        требовать(isinstance(экземпляр, str) and len(экземпляр) == 64, "повреждённый экземпляр")
        требовать("содержимое" in сообщение and isinstance(сообщение["позиция"], dict)
            and isinstance(сообщение["происхождение"], str), "повреждённый оригинал")
        экземпляры.append(экземпляр)
    известные = set(экземпляры)
    требовать(len(известные) == len(экземпляры), "повтор экземпляра сообщения")
    требовать(значение["контекст"]["экземпляры"] == экземпляры, "контекст не соответствует сообщениям")
    обработка = {}
    for номер, запись in enumerate(остаток):
        экземпляр = запись["экземпляр"]
        требовать(экземпляр in известные and экземпляр not in обработка, "неизвестный или повторный остаток")
        требовать(isinstance(запись["причины"], list) and all(isinstance(причина, str) for причина in запись["причины"]),
            "повреждённые причины остатка")
        требовать(isinstance(запись["поздние"], list) and all(поздний in известные for поздний in запись["поздние"]),
            "поздняя ссылка отсутствует в сообщениях")
        обработка[экземпляр] = (номер, запись)
    for ключ in ("полнота_источника", "разбор_сообщений_завершён", "завершение_задачи_доказано"):
        требовать(type(значение[ключ]) is bool, "повреждённый признак состояния")
    for ключ in ("неполный_хвост", "непроверенный_хвост", "граница_заключительной_сверки"):
        требовать(type(значение[ключ]) is int and значение[ключ] >= 0, "повреждённая граница источника")
    требовать(not значение["завершение_задачи_доказано"], "остаток не доказывает завершение задачи")
    требовать(значение["разбор_сообщений_завершён"] == (значение["полнота_источника"] and not остаток),
        "противоречивый признак завершения разбора")
    требовать(not значение["полнота_источника"] or not (значение["неполный_хвост"] or значение["непроверенный_хвост"]),
        "полный источник не может иметь непроверенный хвост")
    return сообщения, обработка


def _семантический_хэш_проверенного(значение):
    хэш = hashlib.sha256()
    кодировщик = json.JSONEncoder(ensure_ascii=False, sort_keys=True,
        separators=(",", ":"), allow_nan=False)
    семантика = {ключ: значение[ключ] for ключ in значение if ключ != "профиль"}
    for часть in кодировщик.iterencode(семантика):
        хэш.update(часть.encode("utf-8"))
    return хэш.hexdigest()


def семантический_хэш(значение):
    """Связать проверенный снимок без изменчивого диагностического профиля."""
    try:
        проверить(значение)
        return _семантический_хэш_проверенного(значение)
    except (KeyError, TypeError, RecursionError, OverflowError) as ошибка:
        raise ValueError("повреждённый результат живого остатка") from ошибка


def _причины_всего(обработка):
    return dict(Counter(причина for _, запись in обработка.values()
        for причина in запись["причины"]))


def _подготовить_живой_снимок(значение, *, источник_перепроверен=False):
    требовать(type(источник_перепроверен) is bool, "повреждённый признак перепроверки источника")
    try:
        сообщения, обработка = проверить(значение)
        for сообщение in сообщения:
            требовать("сырой_объект" in сообщение and "дубли" in сообщение,
                "живой оригинал не содержит сырые части или дубли")
            требовать(isinstance(сообщение["дубли"], list), "повреждённый список дублей")
        снимок = _семантический_хэш_проверенного(значение)
        описание = {
            "схема": "fum.сеанс-живых-страниц-остатка.1",
            "задача": значение["задача"],
            "снимок_sha256": снимок,
            "источник": значение["источник"],
            "история_sha256": значение["история_sha256"],
            "контекст": {ключ: значение["контекст"][ключ] for ключ in ("граница", "sha256")},
            "состояние": {ключ: значение[ключ] for ключ in ("полнота_источника", "неполный_хвост",
                "непроверенный_хвост", "граница_заключительной_сверки", "разбор_сообщений_завершён")},
            "всего_сообщений": len(сообщения),
            "всего_необработанных": len(обработка),
            "полный_результат_сохранён": False,
            "живой_источник_перепроверен_при_создании_снимка": источник_перепроверен,
            "завершение_задачи_доказано": False,
        }
        требовать(len(закодировать(описание)) <= МАКСИМУМ_БАЙТОВ_ДЕСКРИПТОРА,
            "дескриптор живого сеанса превышает предел")
        return сообщения, обработка, снимок, описание
    except (KeyError, TypeError, RecursionError, OverflowError) as ошибка:
        raise ValueError("повреждённый результат живого остатка") from ошибка


def описать_живой_сеанс(значение):
    return _подготовить_живой_снимок(значение, источник_перепроверен=False)[3]


def _представить_живое(значение, сообщения, обработка, снимок, *, начало, число, максимум_байтов,
        источник_перепроверен):
    требовать(type(начало) is int and 0 <= начало <= len(сообщения),
        "начало страницы за границей сообщений")
    требовать(type(число) is int and 1 <= число <= 1000,
        "число сообщений должно быть от 1 до 1000")
    требовать(type(максимум_байтов) is int and 100 <= максимум_байтов <= МАКСИМУМ_БАЙТОВ_ЖИВОЙ_СТРАНИЦЫ,
        "неверный бюджет байтов живой страницы")
    конец = min(len(сообщения), начало + число)
    страница = []
    for номер in range(начало, конец):
        сообщение = сообщения[номер]
        пара = обработка.get(сообщение["экземпляр"])
        запись = None if пара is None else пара[1]
        страница.append({
            "оригинал": dict(сообщение),
            "индекс_оригинала": номер,
            "индекс_обработки": None if пара is None else пара[0],
            "причины": [] if запись is None else запись["причины"],
            "число_поздних": 0 if запись is None else len(запись["поздние"]),
            "последняя_обработка": None if запись is None else запись["последняя_обработка"],
        })
    показанные = {сообщение["экземпляр"] for сообщение in сообщения[начало:конец]}
    результат = {
        "схема": "fum.страница-живого-остатка.1",
        "задача": значение["задача"],
        "снимок_sha256": снимок,
        "источник": значение["источник"],
        "история_sha256": значение["история_sha256"],
        "контекст": {ключ: значение["контекст"][ключ] for ключ in ("граница", "sha256")},
        "состояние": {ключ: значение[ключ] for ключ in ("полнота_источника", "неполный_хвост",
            "непроверенный_хвост", "граница_заключительной_сверки", "разбор_сообщений_завершён")},
        "всего_сообщений": len(сообщения),
        "всего_необработанных": len(обработка),
        "непоказанных_необработанных": len(set(обработка) - показанные),
        "причины_всего": _причины_всего(обработка),
        "начало": начало,
        "конец": конец,
        "следующее_начало": конец if конец < len(сообщения) else None,
        "показаны_все_сообщения": начало == 0 and конец == len(сообщения),
        "сообщения": страница,
        "полный_результат_сохранён": False,
        "живой_источник_перепроверен_при_создании_снимка": источник_перепроверен,
        "завершение_задачи_доказано": False,
        "предупреждение": "Страница не подтверждает обработку или завершение задачи. Полный результат не сохранён; страницы действительны только внутри этого неизменяемого сеанса снимка.",
    }
    требовать(len(закодировать(результат)) <= максимум_байтов,
        "страница превышает бюджет: уменьшите число сообщений или явно увеличьте бюджет; данные не усечены")
    return результат


def представить_живое(значение, ожидаемый_хэш, *, начало=0, число=20, максимум_байтов=16000):
    сообщения, обработка, снимок, _ = _подготовить_живой_снимок(
        значение, источник_перепроверен=False)
    требовать(ожидаемый_хэш == снимок, "не совпал ожидаемый семантический хэш снимка")
    return _представить_живое(значение, сообщения, обработка, снимок,
        начало=начало, число=число, максимум_байтов=максимум_байтов,
        источник_перепроверен=False)


def _разобрать_команду(строка):
    требовать(isinstance(строка, str) and строка.endswith("\n"),
        "команда живого сеанса не завершена переводом строки")
    требовать(len(строка.encode("utf-8")) <= МАКСИМУМ_БАЙТОВ_КОМАНДЫ,
        "команда живого сеанса превышает предел")
    try:
        return json.loads(строка, object_pairs_hook=объект,
            parse_constant=lambda константа: требовать(False, "неконечное число JSON"))
    except (json.JSONDecodeError, UnicodeError, RecursionError) as ошибка:
        raise ValueError("повреждённая команда живого сеанса") from ошибка


def вести_живые_страницы(значение, вход, выход, *, источник_перепроверен=False):
    """Один раз проверить снимок и обслуживать строгие JSONL-запросы страниц."""
    сообщения, обработка, снимок, описание = _подготовить_живой_снимок(
        значение, источник_перепроверен=источник_перепроверен)
    выход.write(закодировать(описание).decode("utf-8"))
    выход.flush()
    while True:
        строка = вход.readline(МАКСИМУМ_БАЙТОВ_КОМАНДЫ + 1)
        требовать(строка != "", "сеанс живых страниц завершён без явной команды")
        команда = _разобрать_команду(строка)
        требовать(isinstance(команда, dict), "команда живого сеанса должна быть объектом")
        схема = команда.get("схема")
        if схема == "fum.завершение-сеанса-живых-страниц.1":
            требовать(set(команда) == {"схема", "снимок_sha256"}, "неверные поля завершения живого сеанса")
            требовать(команда["снимок_sha256"] == снимок, "не совпал ожидаемый семантический хэш снимка")
            return 0 if значение["разбор_сообщений_завершён"] else 3
        требовать(схема == "fum.запрос-страницы-живого-остатка.1", "неизвестная команда живого сеанса")
        требовать(set(команда) == {"схема", "снимок_sha256", "начало", "число", "максимум_байтов"},
            "неверные поля запроса живой страницы")
        требовать(команда["снимок_sha256"] == снимок, "не совпал ожидаемый семантический хэш снимка")
        страница = _представить_живое(значение, сообщения, обработка, снимок,
            начало=команда["начало"], число=команда["число"], максимум_байтов=команда["максимум_байтов"],
            источник_перепроверен=источник_перепроверен)
        выход.write(закодировать(страница).decode("utf-8"))
        выход.flush()


def представить(данные, ожидаемый_хэш, *, начало=0, число=20, максимум_байтов=16000):
    требовать(isinstance(данные, bytes) and len(данные) <= 128 * 1024 * 1024, "слишком большой или неверный полный результат")
    фактический_хэш = hashlib.sha256(данные).hexdigest()
    требовать(ожидаемый_хэш == фактический_хэш, "не совпал ожидаемый хэш полного результата")
    try:
        значение = json.loads(данные, object_pairs_hook=объект,
            parse_constant=lambda константа: требовать(False, "неконечное число JSON"))
        сообщения, обработка = проверить(значение)
        требовать(type(начало) is int and 0 <= начало <= len(сообщения), "начало страницы за границей сообщений")
        требовать(type(число) is int and 1 <= число <= 1000, "число сообщений должно быть от 1 до 1000")
        требовать(type(максимум_байтов) is int and 100 <= максимум_байтов <= 1024 * 1024, "неверный бюджет байтов")
        конец = min(len(сообщения), начало + число)
        страница = []
        for номер in range(начало, конец):
            сообщение = сообщения[номер]
            пара = обработка.get(сообщение["экземпляр"])
            запись = None if пара is None else пара[1]
            страница.append({"оригинал": {ключ: сообщение[ключ] for ключ in
                ("экземпляр", "позиция", "происхождение", "содержимое")},
                "указатель_оригинала": "/".join(("", "сообщения", str(номер))),
                "указатель_обработки": None if пара is None else "/".join(("", "остаток", str(пара[0]))),
                "причины": [] if запись is None else запись["причины"],
                "число_поздних": 0 if запись is None else len(запись["поздние"]),
                "последняя_обработка": None if запись is None else запись["последняя_обработка"]})
        показанные = {сообщение["экземпляр"] for сообщение in сообщения[начало:конец]}
        результат = {"схема": "fum.страница-остатка.1", "задача": значение["задача"],
            "полный_результат": {"sha256": фактический_хэш, "байты": len(данные)},
            "источник": значение["источник"], "история_sha256": значение["история_sha256"],
            "контекст": {ключ: значение["контекст"][ключ] for ключ in ("граница", "sha256")},
            "состояние": {ключ: значение[ключ] for ключ in ("полнота_источника", "неполный_хвост",
                "непроверенный_хвост", "граница_заключительной_сверки", "разбор_сообщений_завершён")},
            "всего_сообщений": len(сообщения), "всего_необработанных": len(обработка),
            "непоказанных_необработанных": len(set(обработка) - показанные),
            "причины_всего": dict(Counter(причина for _, запись in обработка.values() for причина in запись["причины"])),
            "начало": начало, "конец": конец, "следующее_начало": конец if конец < len(сообщения) else None,
            "показаны_все_сообщения": начало == 0 and конец == len(сообщения),
            "сообщения": страница, "указатель_полного_остатка": "/".join(("", "остаток")),
            "живой_источник_перепроверен": False, "завершение_задачи_доказано": False,
            "предупреждение": "Страница не подтверждает обработку. Поздние связи, сырые части и дубли доступны по указателям полного результата; его актуальность проверяется отдельным чтением источника."}
        требовать(len(закодировать(результат)) <= максимум_байтов,
            "страница превышает бюджет: уменьшите число сообщений или явно увеличьте бюджет; данные не усечены")
        return результат
    except (KeyError, TypeError, UnicodeError, RecursionError) as ошибка:
        raise ValueError("повреждённый полный результат") from ошибка

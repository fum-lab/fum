def завершить_удерживаемый_процесс(процесс):
    """Actual child handle нашего Popen, не PID из файла; до wait PID не переиспользуется."""
    if процесс.returncode is None:
        процесс.send_signal(signal.SIGTERM)
        if процесс.returncode is None:
            try:
                if os.getpgid(процесс.pid) == os.getsid(процесс.pid) == процесс.pid:
                    os.killpg(процесс.pid, signal.SIGCONT)
            except ProcessLookupError:
                pass
    try:
        return процесс.communicate(timeout=5)
    except subprocess.TimeoutExpired:
        процесс.kill()
        return процесс.communicate(timeout=5)


def очистить_проверочные_группы(выбор, процесс, рабочий, причина):
    """Только живой удерживаемый worker и его реальные direct children, без authority JSON PID."""
    наблюдение = {'схема': 'fum.очистка-фикстурной-проверки.1', 'причина': причина,
        'worker': рабочий, 'child': [], 'сигналы': [], 'unknown': None}
    try:
        сверить_собственный_процесс(выбор, рабочий, os.getpid())
        os.killpg(рабочий['pid'], signal.SIGSTOP)
        наблюдение['сигналы'].append({'pgid': рабочий['pid'], 'сигнал': 'SIGSTOP'})
        # Пока parent STOP и не reaped, PID parent удерживается, отдельный child не угадывается по файлу.
        таблица = прочитать_процессы(выбор)
        отдельные = [с for с in таблица.values() if с['ppid'] == рабочий['pid']
                     and с['pid'] == с['pgid'] and с['uid'] == os.getuid()]
        for дочерний in отдельные:
            сверить_собственный_процесс(выбор, дочерний, рабочий['pid'])
            os.killpg(дочерний['pid'], signal.SIGKILL)
            наблюдение['child'].append(дочерний)
            наблюдение['сигналы'].append({'pgid': дочерний['pid'], 'сигнал': 'SIGKILL'})
        # TERM ставится до CONT: штатная обёртка получает шанс reap и terminalize собственный отказ.
        os.killpg(рабочий['pid'], signal.SIGTERM)
        os.killpg(рабочий['pid'], signal.SIGCONT)
        наблюдение['сигналы'].extend([{'pgid': рабочий['pid'], 'сигнал': с} for с in ('SIGTERM', 'SIGCONT')])
        try:
            вывод, ошибки = процесс.communicate(timeout=5)
        except subprocess.TimeoutExpired:
            # Worker ещё удерживается actual Popen; после CONT допускается новый незавершённый spawn.
            сверить_собственный_процесс(выбор, рабочий, os.getpid())
            os.killpg(рабочий['pid'], signal.SIGSTOP)
            for дочерний in прочитать_процессы(выбор).values():
                if дочерний['ppid'] == рабочий['pid'] and дочерний['pid'] == дочерний['pgid']:
                    сверить_собственный_процесс(выбор, дочерний, рабочий['pid'])
                    os.killpg(дочерний['pid'], signal.SIGKILL)
                    наблюдение['child'].append(дочерний)
            os.killpg(рабочий['pid'], signal.SIGKILL)
            вывод, ошибки = процесс.communicate(timeout=5)
        группы = {рабочий['pid'], *(с['pid'] for с in наблюдение['child'])}
        for группа in группы:
            try:
                os.killpg(группа, 0)
            except ProcessLookupError:
                continue
            raise ValueError('После reap осталась наблюдённая группа; очистка неизвестна')
        наблюдение['группы_завершены'] = True
    except (OSError, ValueError, subprocess.TimeoutExpired) as ошибка:
        наблюдение['unknown'] = str(ошибка)
        наблюдение['группы_завершены'] = False
        # После exited/reaped worker секундный ps birth не даёт права сигналить orphan/чужую PG.
        вывод, ошибки = завершить_удерживаемый_процесс(процесс)
    наблюдение['код_worker'] = процесс.returncode
    новый_частный_файл(выбор.частное / 'очистка-проверки.json', байты(наблюдение))
    return вывод, ошибки


def выполнить_штатную_проверку(выбор, контур):
    проверка = выбор.выбор['проверка']
    допуск.требовать(type(проверка['тайм_аут']) is int and 0 < проверка['тайм_аут'] <= 60,
                     'Нужен конечный fixture timeout')
    обёртка = контур.загрузить('штатная_обёртка', ПУТЬ_ОБЁРТКИ)
    исходный_процесс = subprocess.Popen
    class НаблюдаемыйПроцесс(исходный_процесс):
        def __init__(сам, *аргументы, **параметры):
            допуск.требовать(аргументы[0] == команда_режима(выбор, 'проверить-предмет')
                and параметры.get('start_new_session') is True
                and параметры['env'].get('FUM_CHECK_RUN_ID') == проверка['идентификатор'],
                'Stock child invocation не равен независимо выбранному проверяющему')
            super().__init__(*аргументы, **параметры)
            try:
                сведения = прочитать_процессы(выбор)[сам.pid]
                сверить_собственный_процесс(выбор, сведения, os.getpid())
                новый_частный_файл(выбор.частное / 'наблюдение-stock-child.json', байты({
                    'схема': 'fum.наблюдение-штатного-child-базиса.1', 'выбор_sha256': выбор.выбор_хэш,
                    'вход_sha256': выбор.вход_хэш, 'проверка': проверка['идентификатор'],
                    'child': сведения, 'форма_вызова_хэш': хэш(байты(аргументы[0]))}))
            except BaseException:
                # Именно этот held Popen создан нами, PID не берётся из редактируемого JSON.
                if сам.poll() is None:
                    os.killpg(сам.pid, signal.SIGKILL)
                сам.wait(timeout=5)
                raise
    class ФасадПроцессов:
        def __getattr__(сам, имя):
            return НаблюдаемыйПроцесс if имя == 'Popen' else getattr(subprocess, имя)
    обёртка.subprocess = ФасадПроцессов()
    код = обёртка.выполнить_запуск(корень_репозитория=выбор.отчёт,
        запрос=Path(проверка['запрос']), название='Проверить точный предмет базиса',
        исполнитель='Фикстурный проверяющий', идентификатор_запуска=проверка['идентификатор'],
        тайм_аут=проверка['тайм_аут'], команда=команда_режима(выбор, 'проверить-предмет'),
        класс_проверки='адресная', приёмочные_раунды=True)
    допуск.требовать(код == 0, 'Штатная содержательная проверка завершилась отказом')
    запуск = прочитать_штатный_запуск(выбор, контур)
    дочерний = читать_частное(выбор.частное / 'дочерний.json')
    результат = {'схема': 'fum.worker-фикстурной-проверки-базиса.1',
        'проверка': проверка['идентификатор'], 'вход_sha256': выбор.вход_хэш,
        'дочерний_sha256': хэш(дочерний),
        'наблюдение_дочернего_sha256': хэш(читать_частное(выбор.частное / 'наблюдение-stock-child.json')),
        'старт_дочернего_sha256': хэш(читать_частное(выбор.частное / 'старт-дочернего.json')),
        'v4': запуск, 'контур': контур.свидетельство()}
    новый_частный_файл(выбор.частное / 'worker.json', байты(результат))


def подготовить_допуск(выбор, контур):
    до = сверить_предмет(выбор)
    прочитать_процессы(выбор)  # До spawn проверить доступность/полноту OS observer.
    команда = команда_режима(выбор, 'проверка-в-обёртке')
    начало = time.perf_counter_ns()
    сигналы = []
    прежние = {номер: signal.getsignal(номер) for номер in (signal.SIGINT, signal.SIGTERM)}
    def принять_сигнал(номер, кадр):
        сигналы.append(signal.Signals(номер).name)
    for номер in прежние:
        signal.signal(номер, принять_сигнал)
    маска = signal.pthread_sigmask(signal.SIG_BLOCK, set(прежние))
    процесс = None
    рабочий = None
    причина = None
    try:
        try:
            процесс = subprocess.Popen(команда, env=чистая_среда(выбор), cwd=выбор.отчёт,
                stdout=subprocess.PIPE, stderr=subprocess.PIPE, start_new_session=True,
                preexec_fn=lambda: signal.pthread_sigmask(signal.SIG_SETMASK, маска))
            рабочий = прочитать_процессы(выбор)[процесс.pid]
            сверить_собственный_процесс(выбор, рабочий, os.getpid())
        finally:
            signal.pthread_sigmask(signal.SIG_SETMASK, маска)
        срок = time.monotonic() + выбор.выбор['проверка']['тайм_аут'] + 8
        while True:
            if сигналы or time.monotonic() >= срок:
                причина = сигналы[-1] if сигналы else 'тайм-аут'
                вывод, ошибки = очистить_проверочные_группы(выбор, процесс, рабочий, причина)
                break
            try:
                вывод, ошибки = процесс.communicate(timeout=min(0.1, max(0.001, срок - time.monotonic())))
                break
            except subprocess.TimeoutExpired:
                continue
    except BaseException:
        if процесс is not None:
            if рабочий is not None:
                вывод, ошибки = очистить_проверочные_группы(выбор, процесс, рабочий, 'ошибка-supervisor')
            else:
                вывод, ошибки = завершить_удерживаемый_процесс(процесс)
                новый_частный_файл(выбор.частное / 'очистка-проверки.json', байты({
                    'схема': 'fum.очистка-фикстурной-проверки.1', 'unknown': 'OS registration не завершена',
                    'код_worker': процесс.returncode, 'worker': None, 'группы_завершены': False}))
            новый_частный_файл(выбор.частное / 'worker.stdout', вывод)
            новый_частный_файл(выбор.частное / 'worker.stderr', ошибки)
        raise
    finally:
        signal.pthread_sigmask(signal.SIG_SETMASK, маска)
        for номер, обработчик in прежние.items():
            signal.signal(номер, обработчик)
    новый_частный_файл(выбор.частное / 'worker.stdout', вывод)
    новый_частный_файл(выбор.частное / 'worker.stderr', ошибки)
    if причина is not None or сигналы or процесс.returncode != 0:
        новый_частный_файл(выбор.частное / 'процесс-отказа-проверки.json', байты({
            'схема': 'fum.отказ-фикстурной-проверки-базиса.1', 'причина': причина,
            'код_завершения': процесс.returncode, 'исполнение_завершено': процесс.returncode is not None,
            'вывод_хэш': хэш(вывод), 'ошибки_хэш': хэш(ошибки)}))
    допуск.требовать(причина is None and not сигналы and процесс.returncode == 0,
                     'Worker не завершился успешно; successful typed не выпускается')
    после = сверить_предмет(выбор)
    допуск.требовать(до == после, 'Предмет изменился до завершения процесса')
    дочерний_байты = читать_частное(выбор.частное / 'дочерний.json')
    байты_рабочего_свидетельства = читать_частное(выбор.частное / 'worker.json')
    дочерний, рабочее_свидетельство = описание(дочерний_байты), описание(байты_рабочего_свидетельства)
    сверить_наблюдение_штатного_процесса(выбор, рабочее_свидетельство, рабочий)
    запуск = прочитать_штатный_запуск(выбор, контур)
    допуск.требовать(рабочее_свидетельство['v4'] == запуск and рабочее_свидетельство['дочерний_sha256'] == хэш(дочерний_байты)
        and рабочее_свидетельство['вход_sha256'] == дочерний['вход_sha256'] == выбор.вход_хэш
        and рабочее_свидетельство['проверка'] == дочерний['проверка'] == запуск['идентификатор']
        and дочерний['выбор_sha256'] == выбор.выбор_хэш
        and дочерний['до'] == дочерний['после'] == до,
        'Raw worker/child/v4 свидетельства расходятся')
    наблюдение = {'схема': 'fum.процесс-проверки-базиса-узла.1',
        'проверка': запуск['идентификатор'], 'выбор_sha256': выбор.выбор_хэш,
        'вход_sha256': выбор.вход_хэш, 'форма_вызова_хэш': хэш(байты(команда)),
        'код_завершения': процесс.returncode, 'исполнение_завершено': True,
        'тайм_аут': False, 'прерывание': None,
        'длительность_наносекунды': time.perf_counter_ns() - начало,
        'вывод_хэш': хэш(вывод), 'ошибки_хэш': хэш(ошибки),
        'worker_sha256': хэш(байты_рабочего_свидетельства), 'child_sha256': хэш(дочерний_байты), 'рабочий_ОС': рабочий,
        'runtime': выбор.выбор['runtime'], 'контур': контур.свидетельство()}
    процесс_хэш = новый_частный_файл(выбор.частное / 'процесс-проверки.json', байты(наблюдение))
    типизированное = {'схема': 'fum.свидетельство-проверки-базиса-узла.1',
        'выбор_sha256': выбор.выбор_хэш, 'вход_sha256': выбор.вход_хэш,
        'предмет': выбор.выбор['предмет'], 'решения_корня': выбор.выбор['решения_корня'],
        'защищённые_продукты': выбор.выбор['защищённые_продукты'], 'v4': запуск,
        'rawprocess_sha256': процесс_хэш, 'до': до, 'после': после,
        'child_контур': дочерний['контур'], 'worker_контур': рабочее_свидетельство['контур'],
        'supervisor_контур': контур.свидетельство()}
    новый_частный_файл(выбор.частное / 'типизированное.json', байты(типизированное))
    return {'проверка': запуск['идентификатор'], 'типизированное_sha256': хэш(байты(типизированное))}


def сверить_контур(выбор, свидетельство, роли):
    поля(свидетельство, ('схема', 'M', 'trusted_base', 'датчик_установлен', 'загрузки'))
    допуск.требовать(свидетельство['схема'] == 'fum.загрузка-фикстурного-контура.1'
        and свидетельство['M'] == выбор.выбор['M']
        and свидетельство['trusted_base'] == 'Внешний issuer, bootstrap и установленный Python/Git runtime'
        and свидетельство['датчик_установлен'] is True
        and type(свидетельство['загрузки']) is list and len(свидетельство['загрузки']) == len(роли),
        'Не подтверждён полный отдельно исполненный контур M')
    пути = {'bootstrap': Path(__file__).resolve().relative_to(выбор.код).as_posix(),
        'admission': ПУТЬ_ДОПУСКА.resolve().relative_to(выбор.код).as_posix(),
        'штатная_обёртка': ПУТЬ_ОБЁРТКИ}
    for загрузка, роль in zip(свидетельство['загрузки'], роли, strict=True):
        поля(загрузка, ('роль', 'путь', 'raw_sha256', 'code_sha256'))
        путь = пути[роль]
        данные = выбор.буферы[путь]
        код = compile(данные, str(выбор.код / путь), 'exec', dont_inherit=True, optimize=sys.flags.optimize)
        допуск.требовать(загрузка == {'роль': роль, 'путь': путь, 'raw_sha256': хэш(данные),
            'code_sha256': хэш(байты(граф_кода(код)))}, 'Состав или код загрузки расходится с независимым M')



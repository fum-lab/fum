    global ПУТЬ_ЗАКРЕПЛЁННОГО_ГИТА
    путь = Path(__file__).with_name('допуск_создания_базиса_узла.py')
    if __name__ != '__main__':
        # Чистые raw6 consumers получают удержанный buffer от доверенного внешнего issuer.
        try:
            данные = УДЕРЖАННЫЙ_БУФЕР_ДОПУСКА
            ожидаемый = ХЭШ_УДЕРЖАННОГО_ДОПУСКА
        except NameError as ошибка:
            raise ValueError('Читающий consumer не получил закреплённый admission buffer') from ошибка
        if type(данные) is not bytes or hashlib.sha256(данные).hexdigest() != ожидаемый:
            raise ValueError('Читающий consumer не получил закреплённый admission buffer')
        return данные
    if '--help' in sys.argv[1:]:
        print(__doc__)
        raise SystemExit(0)
    def значение(ключ):
        if sys.argv.count(ключ) != 1 or sys.argv.index(ключ) + 1 == len(sys.argv):
            raise ValueError('Bootstrap требует единственный независимый корневой выбор')
        return sys.argv[sys.argv.index(ключ) + 1]
    выбор_путь = Path(значение('--выбор'))
    if (not выбор_путь.is_absolute() or выбор_путь != выбор_путь.resolve()
            or any(п.is_symlink() for п in (выбор_путь, *выбор_путь.parents))):
        raise ValueError('Bootstrap выбор имеет неподтверждённый физический адрес')
    сведения = выбор_путь.lstat()
    if (not stat.S_ISREG(сведения.st_mode) or сведения.st_nlink != 1
            or сведения.st_uid != os.getuid() or stat.S_IMODE(сведения.st_mode) != 0o600):
        raise ValueError('Bootstrap выбор не является приватным обычным файлом')
    сырое = выбор_путь.read_bytes()
    if hashlib.sha256(сырое).hexdigest() != значение('--выбор-sha256'):
        raise ValueError('Bootstrap выбор не равен независимо выбранному SHA')
    выбор = json.loads(сырое)
    источник_кода = выбор['M']
    корень = Path(источник_кода['корень'])
    гит = Path(выбор['runtime']['git']['путь'])
    if (корень != корень.resolve() or any(п.is_symlink() for п in (корень, *корень.parents))
            or not (корень / '.git').is_dir() or (корень / '.git').is_symlink()
            or re.fullmatch('[0-9a-f]{40}', источник_кода['коммит']) is None
            or гит != гит.resolve()
            or hashlib.sha256(гит.read_bytes()).hexdigest() != выбор['runtime']['git']['sha256']):
        raise ValueError('Bootstrap M/Git не закреплены')
    среда = {'PATH': str(гит.parent) + ':/usr/bin:/bin', 'GIT_CONFIG_NOSYSTEM': '1',
        'GIT_CONFIG_GLOBAL': os.devnull, 'GIT_NO_LAZY_FETCH': '1', 'GIT_NO_REPLACE_OBJECTS': '1'}
    ПУТЬ_ЗАКРЕПЛЁННОГО_ГИТА = str(гит)
    def блоб(имя):
        if not имя or Path(имя).is_absolute() or any(п in ('', '.', '..') for п in имя.split('/')):
            raise ValueError('Неизвестный bootstrap путь M')
        return subprocess.check_output([str(гит), '--no-optional-locks', '--no-replace-objects',
            '-c', 'core.fsmonitor=false', '-c', 'core.hooksPath=' + os.devnull,
            '-c', 'gc.auto=0', '-c', 'maintenance.auto=false', '-c', 'trace2.normalTarget=0',
            '-c', 'trace2.eventTarget=0', '-c', 'trace2.perfTarget=0', '-c', 'protocol.allow=never',
            '-C', str(корень), 'cat-file', 'blob', источник_кода['коммит'] + ':' + имя],
            env=среда, stderr=subprocess.PIPE, timeout=20)
    манифест = блоб(источник_кода['путь'])
    if hashlib.sha256(манифест).hexdigest() != источник_кода['sha256']:
        raise ValueError('Bootstrap manifest не равен M')
    относительный = путь.resolve().relative_to(корень).as_posix()
    записи = [з for з in json.loads(манифест)['контракты'] if з['путь'] == относительный]
    if len(записи) != 1:
        raise ValueError('Bootstrap helper отсутствует или повторён в M')
    данные = блоб(относительный)
    if hashlib.sha256(данные).hexdigest() != записи[0]['sha256']:
        raise ValueError('Bootstrap helper blob не равен M')
    return данные



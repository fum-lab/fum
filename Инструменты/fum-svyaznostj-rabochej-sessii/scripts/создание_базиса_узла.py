class ВыборБазиса:
    """Отдельно выбранный fixture issuer вход; это не production/Desktop authority."""
    def __init__(сам, выбор_путь, выбор_хэш, вход_путь, вход_хэш):
        сам.выбор_путь = допуск.физический_корень(выбор_путь)
        сам.выбор_хэш = выбор_хэш
        сам.вход_путь = допуск.физический_корень(вход_путь)
        сам.вход_хэш = вход_хэш
        сам.выбор_байты = читать_частное(сам.выбор_путь, выбор_хэш)
        сам.вход_байты = читать_частное(сам.вход_путь, вход_хэш)
        сам.выбор = описание(сам.выбор_байты)
        поля(сам.выбор, ('схема', 'режим', 'M', 'C0', 'ACT_B', 'предмет', 'адрес',
            'исполнитель', 'координатор', 'поколение', 'нативный_срез', 'защищённые_продукты',
            'решения_корня', 'проверка', 'частный_каталог', 'идентичность', 'runtime'))
        допуск.требовать(сам.выбор['схема'] == 'fum.выбор-фикстурного-базиса.1'
            and сам.выбор['режим'] == 'изолированная-фикстура', 'Производственный эффект не разрешён')
        вход = поля(описание(сам.вход_байты), ('схема', 'выбор_sha256', 'предмет'))
        допуск.требовать(вход == {'схема': 'fum.создание-базиса-узла.1',
            'выбор_sha256': выбор_хэш, 'предмет': сам.выбор['предмет']},
            'Maker input подменяет независимо выбранный предмет')
        сам.корень = допуск.физический_корень(сам.выбор['адрес']['корень'])
        сам.частное = допуск.физический_корень(сам.выбор['частный_каталог'])
        сам.код = допуск.физический_корень(сам.выбор['M']['корень'])
        сам.отчёт = допуск.физический_корень(сам.выбор['проверка']['корень'])
        область = сам.корень.parent
        допуск.требовать(область.name.startswith('fum-basis-fixture-')
            and область.stat().st_uid == os.getuid() and stat.S_IMODE(область.stat().st_mode) == 0o700
            and сам.частное.parent == сам.код.parent == сам.отчёт.parent == область
            and len({сам.корень, сам.частное, сам.код, сам.отчёт}) == 4,
            'Эффект разрешён только в собственной временной изолированной fixture области')
        сам.контракты = описание(прочитать_выбор_блоба(сам.выбор['M']))
        поля(сам.контракты, ('схема', 'контракты'))
        допуск.требовать(сам.контракты['схема'] == 'fum.фикстурный-контур-базиса.1',
                         'Неизвестный исполняемый контур')
        сам.буферы = {}
        for запись in сам.контракты['контракты']:
            поля(запись, ('путь', 'sha256'))
            имя = допуск.имя_индекса(запись['путь'].encode())
            допуск.требовать(имя not in сам.буферы and имя.endswith('.py'), 'Неизвестный контракт кода')
            источник = {'корень': str(сам.код), 'коммит': сам.выбор['M']['коммит'],
                        'путь': имя, 'sha256': запись['sha256']}
            сам.буферы[имя] = прочитать_выбор_блоба(источник)
        сам.сверить_источники()

    def сверить_источники(сам):
        допуск.требовать(читать_частное(сам.выбор_путь) == сам.выбор_байты
                         and читать_частное(сам.вход_путь) == сам.вход_байты,
                         'Корневой выбор или maker input изменился')
        for имя, данные in сам.буферы.items():
            допуск.требовать(допуск.обычные_байты(сам.код / имя, корень=сам.код) == данные,
                             'Физическое зеркало M не равно закреплённому буферу')
        поля(сам.выбор['runtime'], ('python', 'git', 'ps'))
        for имя in ('python', 'git', 'ps'):
            запись = поля(сам.выбор['runtime'][имя], ('путь', 'sha256'))
            путь = допуск.физический_корень(запись['путь'])
            допуск.требовать(хэш(путь.read_bytes()) == запись['sha256'], 'Runtime binary изменился')
        допуск.требовать(str(Path(sys.executable).resolve()) == сам.выбор['runtime']['python']['путь']
                         and str(Path(shutil.which('git')).resolve()) == сам.выбор['runtime']['git']['путь'],
                         'Запуск использует другой interpreter/Git')


def граф_кода(код):
    def константа(значение):
        if type(значение) is types.CodeType:
            return ['code', граф_кода(значение)]
        if type(значение) is bytes:
            return ['bytes', значение.hex()]
        if type(значение) in (tuple, frozenset):
            элементы = [константа(э) for э in значение]
            return [type(значение).__name__, sorted(элементы, key=lambda э: байты(э))
                    if type(значение) is frozenset else элементы]
        if type(значение) is float:
            return ['float', значение.hex()]
        if type(значение) is complex:
            return ['complex', значение.real.hex(), значение.imag.hex()]
        if type(значение) is slice:
            return ['slice', константа(значение.start), константа(значение.stop), константа(значение.step)]
        if значение is Ellipsis:
            return ['ellipsis']
        допуск.требовать(значение is None or type(значение) in (bool, int, str),
                         'Неизвестная константа исполняемого кода: ' + type(значение).__name__)
        return [type(значение).__name__, значение]
    имена = ('co_argcount', 'co_posonlyargcount', 'co_kwonlyargcount', 'co_nlocals',
             'co_stacksize', 'co_flags', 'co_code', 'co_names', 'co_varnames',
             'co_filename', 'co_name', 'co_qualname', 'co_firstlineno', 'co_linetable',
             'co_exceptiontable', 'co_freevars', 'co_cellvars')
    return {**{имя: константа(getattr(код, имя)) for имя in имена},
            'co_consts': [константа(э) for э in код.co_consts]}


class КонтурЗагрузки:
    """Наблюдатель закреплённых project buffers, при доверенных bootstrap/runtime."""
    def __init__(сам, выбор):
        сам.выбор = выбор
        сам.события = []
        сам.разрешённые = {}
        сам.разрешение_исполнения = None
        сам.загрузчик = type(сам).загрузить.__code__
        сам.сверщик = сверить_контур.__code__
        сам.проверен_датчик = False
        сам.системная_основа = Path(sys.base_prefix).resolve()
        for путь, данные, код, роль in (
                (Path(__file__).resolve(), БАЙТЫ_СОЗДАТЕЛЯ, КОД_ВЫПОЛНЕНИЯ, 'bootstrap'),
                (ПУТЬ_ДОПУСКА.resolve(), БАЙТЫ_ДОПУСКА, КОД_ДОПУСКА, 'admission')):
            имя = путь.relative_to(выбор.код).as_posix()
            допуск.требовать(выбор.буферы.get(имя) == данные, 'Bootstrap не закреплён в M')
            эталон = compile(данные, str(путь), 'exec', dont_inherit=True, optimize=sys.flags.optimize)
            допуск.требовать(граф_кода(эталон) == граф_кода(код),
                             'Фактически загруженный код не равен буферу M')
            сам.разрешённые[id(код)] = код
            сам.события.append({'роль': роль, 'путь': имя, 'raw_sha256': хэш(данные),
                               'code_sha256': хэш(байты(граф_кода(код)))})
        sys.addaudithook(сам.наблюдать)
        sys.audit('fum.проверить-наблюдатель-базиса', id(сам))
        допуск.требовать(сам.проверен_датчик, 'Наблюдатель исполнения не установился')

    def наблюдать(сам, событие, аргументы):
        if событие == 'fum.проверить-наблюдатель-базиса':
            if аргументы == (id(сам),):
                сам.проверен_датчик = True
            return
        if событие == 'compile':
            данные, имя = аргументы
            путь = Path(имя)
            вызывающий = sys._getframe(1).f_code
            допуск.требовать(вызывающий is сам.загрузчик or вызывающий is сам.сверщик,
                             'Неизвестное место compile вне конечного контура M')
            допуск.требовать(путь.is_absolute() and путь.is_relative_to(сам.выбор.код),
                             'Project compile не имеет точного пути M')
            относительный = путь.relative_to(сам.выбор.код).as_posix()
            допуск.требовать(type(данные) is bytes and сам.выбор.буферы.get(относительный) == данные,
                             'Неизвестный или изменённый project compile buffer')
            return
        if событие == 'exec':
            код = аргументы[0]
            допуск.требовать(sys._getframe(1).f_code is сам.загрузчик
                and сам.разрешённые.get(id(код)) is код and сам.разрешение_исполнения is код,
                'Exec не имеет одноразового разрешения точного загрузчика M')
            сам.разрешение_исполнения = None
            return
        if событие in ('code.__new__', 'function.__new__'):
            raise ValueError('Динамический code/function object вне конечного контура M')

    def загрузить(сам, имя, путь):
        допуск.требовать(путь in сам.выбор.буферы, 'Модуль не выбран независимым M')
        данные = сам.выбор.буферы[путь]
        имя_компиляции = str(сам.выбор.код / путь)
        код = compile(данные, имя_компиляции, 'exec', dont_inherit=True, optimize=sys.flags.optimize)
        сам.разрешённые[id(код)] = код
        модуль = types.ModuleType(имя)
        модуль.__file__ = имя_компиляции
        допуск.требовать(сам.разрешение_исполнения is None, 'Незавершённое разрешение exec')
        сам.разрешение_исполнения = код
        try:
            exec(код, модуль.__dict__)
            допуск.требовать(сам.разрешение_исполнения is None, 'Фактический exec не был наблюдён')
        finally:
            сам.разрешение_исполнения = None
        сам.события.append({'роль': имя, 'путь': путь, 'raw_sha256': хэш(данные),
                           'code_sha256': хэш(байты(граф_кода(код)))})
        return модуль

    def свидетельство(сам):
        сам.выбор.сверить_источники()
        return {'схема': 'fum.загрузка-фикстурного-контура.1', 'M': сам.выбор.выбор['M'],
                'trusted_base': 'Внешний issuer, bootstrap и установленный Python/Git runtime',
                'датчик_установлен': сам.проверен_датчик, 'загрузки': list(сам.события)}


def сверить_защиту_после_создания(выбор, каталог):
    """Сверить прежний полный stage0 и рабочие пути при уже созданном HEAD=B."""
    индекс = каталог / 'index'
    снимки = {}
    до = допуск.обычные_байты(индекс, снимки, каталог)
    ожидаемые = выбор.выбор['защищённые_продукты']
    записи = b''.join((з['режим'] + ' ' + з['объект'] + ' 0\t' + з['путь']).encode()
                     + b'\0' for з in ожидаемые)
    флаги = b''.join(('H ' + з['путь']).encode() + b'\0' for з in ожидаемые)
    допуск.требовать(допуск.гит(выбор.корень, 'ls-files', '--stage', '-z') == записи
        and допуск.гит(выбор.корень, 'ls-files', '-v', '-z') == флаги,
        'Полный защищённый stage0 изменился после создания')
    for запись in ожидаемые:
        имя = допуск.имя_индекса(запись['путь'].encode())
        путь = выбор.корень / имя
        данные = допуск.обычные_байты(путь, снимки, выбор.корень)
        режим = '100755' if путь.stat().st_mode & stat.S_IXUSR else '100644'
        допуск.требовать(хэш(данные) == запись['sha256']
            and допуск.объект_по_байтам('blob', данные) == запись['объект']
            and режим == запись['режим'], 'Защищённые рабочие байты или режим изменились после создания')
    допуск.сверить_объекты_дерева(выбор.корень, выбор.выбор['предмет']['дерево'])
    for путь, (данные, отпечаток, корень_снимка) in снимки.items():
        допуск.требовать(допуск.обычные_байты(путь, корень=корень_снимка) == данные
            and допуск.отпечаток_пути(путь, корень_снимка) == отпечаток,
            'Защищённый путь изменился во время читающего повтора')
    допуск.требовать(допуск.обычные_байты(индекс) == до
        and допуск.гит(выбор.корень, 'ls-files', '--stage', '-z') == записи
        and допуск.гит(выбор.корень, 'ls-files', '-v', '-z') == флаги,
        'Защищённый индекс изменился во время читающего повтора')


def сверить_предмет(выбор, *, после_создания=False):
    выбор.сверить_источники()
    данные = выбор.выбор
    адрес = поля(данные['адрес'], ('корень', 'ветка', 'git_dir', 'common_dir', 'ODB', 'uid',
        'устройство', 'inode', 'HEAD_sha256', 'ref_sha256', 'git_каталоги', 'config_sha256',
        'прочие_refs', 'исходные_объекты', 'замок'))
    сведения_замка = поля(адрес['замок'], ('путь', 'uid', 'устройство', 'inode', 'sha256'))
    путь_замка = Path(сведения_замка['путь'])
    допуск.требовать(путь_замка == выбор.частное / 'замок-предмета'
        and хэш(читать_частное(путь_замка)) == сведения_замка['sha256'], 'Подменён выбранный замок предмета')
    физический_замок = путь_замка.lstat()
    допуск.требовать([физический_замок.st_uid, физический_замок.st_dev, физический_замок.st_ino]
        == [сведения_замка['uid'], сведения_замка['устройство'], сведения_замка['inode']],
        'Замок предмета заменён другим поколением')
    for имя in ('uid', 'устройство', 'inode'):
        допуск.требовать(type(адрес[имя]) is int and адрес[имя] >= 0, 'Неоднозначное число адреса')
    сведения = выбор.корень.stat()
    допуск.требовать((сведения.st_uid, сведения.st_dev, сведения.st_ino)
        == (адрес['uid'], адрес['устройство'], адрес['inode']), 'Подменён владелец или физическая область')
    каталог = допуск.собственная_гит_база(выбор.корень)
    допуск.требовать(адрес['git_dir'] == адрес['common_dir'] == str(каталог)
        and адрес['ODB'] == str(каталог / 'objects') and type(адрес['ветка']) is str
        and адрес['ветка'].startswith('refs/heads/'), 'Подменён полный адрес базы')
    допуск.требовать(type(адрес['git_каталоги']) is dict
        and set(адрес['git_каталоги']) == {'', 'objects', 'refs', 'refs/heads', 'logs', 'logs/refs', 'logs/refs/heads'},
        'Не закреплён полный состав каталогов метаданных')
    for имя, ожидаемые in адрес['git_каталоги'].items():
        сведения_каталога = (каталог / имя).lstat()
        допуск.требовать([сведения_каталога.st_uid, сведения_каталога.st_dev, сведения_каталога.st_ino,
            сведения_каталога.st_mode] == ожидаемые, 'Подменена физическая идентичность Git-каталога')
    допуск.требовать(хэш(допуск.обычные_байты(каталог / 'config')) == адрес['config_sha256'],
                     'Подменена локальная Git-конфигурация')
    прочие = {п.relative_to(каталог).as_posix(): хэш(допуск.обычные_байты(п))
        for п in (каталог / 'refs').rglob('*') if п.is_file()
        and п.relative_to(каталог).as_posix() != адрес['ветка']}
    допуск.требовать(прочие == адрес['прочие_refs'], 'Изменены посторонние refs')
    for имя, ожидаемый in адрес['исходные_объекты'].items():
        допуск.требовать(имя.startswith('objects/') and хэш(допуск.обычные_байты(каталог / имя,
            корень=каталог)) == ожидаемый, 'Изменены исходные байты собственной ODB')
    сырая_голова = допуск.обычные_байты(каталог / 'HEAD')
    допуск.требовать(сырая_голова == ('ref: ' + адрес['ветка'] + '\n').encode()
        and хэш(сырая_голова) == адрес['HEAD_sha256'], 'Подменён сырой HEAD или полный ref')
    привязки = {имя: данные[имя] for имя in ('M', 'предмет', 'адрес', 'исполнитель',
         'координатор', 'поколение', 'нативный_срез', 'защищённые_продукты')}
    for имя, схема in (('C0', 'fum.фикстурное-поручение-базиса.1'),
                       ('ACT_B', 'fum.фикстурный-ACT-базиса.1')):
        актуальное = описание(прочитать_выбор_блоба(данные[имя]))
        допуск.требовать(актуальное == {'схема': схема, **привязки},
                         'Независимые C0/ACT_B не разрешают данный предмет/адрес/поколение')
    for имя in ('исполнитель', 'координатор', 'поколение'):
        допуск.требовать(type(данные[имя]) is str
            and re.fullmatch(r'[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}', данные[имя]),
            'Нужен точный UUID происхождения или поколения')
    срез = поля(данные['нативный_срез'], ('путь', 'sha256'))
    сырое = читать_частное(срез['путь'], срез['sha256'])
    допуск.требовать(сырое.endswith(b'\n') and len(сырое.splitlines()) == 1,
                     'Нужен завершённый одноэкземплярный fixture native срез')
    ожидаемое = {'type': 'session_meta', 'payload': {'id': данные['исполнитель'],
        'cwd': str(выбор.корень), 'source': 'контролируемая-фикстура',
        'координатор': данные['координатор'], 'поколение': данные['поколение']}}
    допуск.требовать(описание(сырое) == ожидаемое,
                     'Fixture native не связывает текущий исполнитель/адрес/поколение')
    допуск.требовать(type(данные['решения_корня']) is list and данные['решения_корня'],
                     'Не выбраны ROOT решения')
    for решение in данные['решения_корня']:
        проверено = описание(прочитать_выбор_блоба(решение))
        допуск.требовать(проверено == {'схема': 'fum.фикстурное-решение-базиса.1',
            'предмет': данные['предмет'], 'защита': данные['защищённые_продукты']},
            'Решение ROOT относится к другому предмету или защите')
    if после_создания:
        сверить_защиту_после_создания(выбор, каталог)
        return {'адрес_sha256': хэш(байты(адрес)), 'native_sha256': срез['sha256'],
                'поколение': данные['поколение']}
    сырая_ветка = допуск.обычные_байты(каталог / адрес['ветка'])
    допуск.требовать(сырая_ветка == (данные['предмет']['основа'] + '\n').encode()
                     and хэш(сырая_ветка) == адрес['ref_sha256'], 'Подменены сырые ref байты/HEAD=K')
    индекс = допуск.сверить_индекс(выбор.корень, данные['предмет'])
    допуск.требовать(индекс['файлы'] == данные['защищённые_продукты'],
                     'Защищённый точный состав не равен реальному stage0')
    объекты = допуск.сверить_объекты_дерева(выбор.корень, данные['предмет']['дерево'])
    return {'предмет': данные['предмет'], 'адрес_sha256': хэш(байты(адрес)),
            'native_sha256': срез['sha256'], 'поколение': данные['поколение'],
            'индекс_sha256': индекс['индекс_sha256'], 'объекты': объекты,
            'решения_корня': данные['решения_корня'],
            'защищённые_продукты': данные['защищённые_продукты']}



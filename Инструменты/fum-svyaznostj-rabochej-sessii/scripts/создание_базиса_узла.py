def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def байты(описание):
    return (json.dumps(описание, ensure_ascii=False, sort_keys=True, indent=2,
                       allow_nan=False) + '\n').encode('utf-8')


def неповторные_поля(пары):
    итог = {}
    for ключ, значение in пары:
        допуск.требовать(ключ not in итог, 'Повторное поле описания')
        итог[ключ] = значение
    return итог


def описание(данные):
    return json.loads(данные, object_pairs_hook=неповторные_поля,
        parse_constant=lambda значение: (_ for _ in ()).throw(ValueError('Нефинитное число')))


def поля(значение, имена):
    допуск.требовать(type(значение) is dict and set(значение) == set(имена),
                     'Неполные или неизвестные поля описания')
    return значение


def читать_частное(путь, ожидаемый=None):
    путь = допуск.физический_корень(путь)
    сведения = путь.lstat()
    допуск.требовать(сведения.st_uid == os.getuid() and stat.S_IMODE(сведения.st_mode) == 0o600
                     and not any((п / '.git').exists() for п in путь.parents),
                     'Нужен собственный приватный файл вне Git')
    данные = допуск.обычные_байты(путь)
    допуск.требовать(ожидаемый is None or хэш(данные) == ожидаемый, 'Подменены приватные байты')
    return данные


def новый_частный_файл(путь, данные):
    путь = Path(путь)
    родитель = допуск.физический_корень(путь.parent)
    допуск.требовать(родитель.stat().st_uid == os.getuid()
                     and stat.S_IMODE(родитель.stat().st_mode) == 0o700
                     and not any((п / '.git').exists() for п in родитель.parents),
                     'Нужен собственный приватный каталог вне Git')
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        with os.fdopen(дескриптор, 'wb', closefd=False) as поток:
            поток.write(данные)
            поток.flush()
            os.fsync(поток.fileno())
    finally:
        os.close(дескриптор)
    каталог = os.open(родитель, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(каталог)
    finally:
        os.close(каталог)
    return хэш(данные)



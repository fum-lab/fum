class ДиагностикаПроцессов:
    """Необязательные stderr-метки; отказ диагностики не меняет исполнение."""
    def __init__(сам, стадия, *, включено=False, писать=None):
        # Pipe вложенного CLI остаётся прежней буферизуемой границей.
        # Менять O_NONBLOCK общего fd или открывать новый FD ABI нельзя.
        сам.включено = включено
        if включено and писать is None:
            try: сам.включено = stat.S_ISREG(os.fstat(2).st_mode)
            except OSError: сам.включено = False
        сам.писать = писать or os.write
        сам.стадия = стадия; сам.номер = 0; сам.процессы = []
        сам.потеря = False

    def событие(сам, событие, **поля):
        if not сам.включено: return
        try:
            данные = (json.dumps({'схема': 'fum.событие-независимого-контура.1',
                'процесс': os.getpid(), 'стадия': сам.стадия, 'событие': событие,
                'монотонное_время_нс': time.monotonic_ns(), **поля},
                ensure_ascii=False, sort_keys=True) + '\n').encode()
            позиция = 0
            while позиция < len(данные):
                число = сам.писать(2, данные[позиция:])
                if not isinstance(число, int) or число <= 0: raise OSError('неполная диагностическая строка')
                позиция += число
        except BaseException:
            сам.потеря = True

    def намерение(сам):
        сам.номер += 1
        сам.событие('процесс-намерение', запуск=сам.номер)
        return сам.номер

    def наблюдать(сам, процесс, номер):
        if not сам.включено: return процесс
        try:
            сам.событие('процесс-запущен', запуск=номер, потомок=процесс.pid, группа=None)
            try:
                группа = os.getpgid(процесс.pid)
            except OSError as ошибка:
                сам.событие('группа-неизвестна', запуск=номер, потомок=процесс.pid,
                    ошибка=type(ошибка).__name__)
            else:
                сам.событие('группа-наблюдена', запуск=номер, потомок=процесс.pid, группа=группа)
            завершён = False
            def терминал():
                nonlocal завершён
                if not завершён and процесс.returncode is not None:
                    завершён = True
                    сам.событие('процесс-завершён', запуск=номер,
                        потомок=процесс.pid, код=процесс.returncode)
            for имя in ('poll', 'wait', 'communicate'):
                исходная = getattr(процесс, имя)
                def обёртка(*аргументы, _исходная=исходная, **именованные):
                    try: return _исходная(*аргументы, **именованные)
                    finally: терминал()
                setattr(процесс, имя, обёртка)
            сам.процессы.append(процесс)
            терминал()
        except BaseException:
            сам.потеря = True
        return процесс

    def сверить_терминалы(сам):
        for процесс in сам.процессы:
            try: процесс.poll()
            except BaseException: сам.потеря = True


def проверить_родителей(пути, *, создаваемые=()):
    """До эффектов; будущие каталоги должны быть выбраны отдельно и точно."""
    создаваемые = {Path(п) for п in создаваемые}
    for значение in пути:
        путь = Path(значение)
        if not путь.is_absolute() or путь.resolve() != путь:
            raise ValueError('нужен физический путь будущей записи')
        for компонент in (путь, *путь.parents):
            if компонент.is_symlink():
                raise ValueError('символический компонент будущей записи')
        родитель = путь.parent
        if родитель in создаваемые and not родитель.exists():
            continue
        if not родитель.is_dir() or not stat.S_ISDIR(родитель.stat().st_mode):
            raise ValueError('родительский каталог отсутствует до первого эффекта')


def файловый_срез(путь):
    путь = Path(путь)
    if not путь.is_absolute() or путь.parent.resolve() != путь.parent:
        raise ValueError('нефизический закреплённый путь')
    if not os.path.lexists(путь):
        return None
    до = путь.lstat()
    def свойства(с):
        return (с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink,
            с.st_size, с.st_mtime_ns, с.st_ctime_ns)
    if not stat.S_ISREG(до.st_mode) or до.st_nlink != 1:
        raise ValueError('необычный закреплённый вход')
    данные = путь.read_bytes()
    if свойства(до) != свойства(путь.lstat()):
        raise ValueError('вход изменился при чтении')
    return свойства(до), данные


class ЗакреплённыеВходы:
    def __init__(сам, пути):
        сам.снимки = {Path(п): файловый_срез(п) for п in пути}
        сам.сверок = 0
        сам.прочитано_байтов = 0
        сам.полных_чтений = 0

    def сверить(сам):
        for путь, ожидаемый in сам.снимки.items():
            if файловый_срез(путь) != ожидаемый:
                raise ValueError('изменились байты или идентичность закреплённого входа: ' + str(путь))
            if ожидаемый is not None:
                сам.прочитано_байтов += len(ожидаемый[1])
                сам.полных_чтений += 1
        сам.сверок += 1


class ЗакреплённыеИдентичности:
    """Дополнение byte guard engine; сам byte guard вызывается без изменений."""
    def __init__(сам, пути):
        сам.снимки = {Path(п): сам.метка(Path(п)) for п in пути}

    @staticmethod
    def метка(путь):
        с = путь.lstat()
        требовать(stat.S_ISREG(с.st_mode) and с.st_nlink == 1, 'необычный вход engine')
        return (с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink, с.st_size, с.st_mtime_ns, с.st_ctime_ns)

    def сверить(сам):
        for путь, метка in сам.снимки.items():
            требовать(сам.метка(путь) == метка, 'изменилась идентичность входа engine')


class ОхраняемыйФайл:
    """Поток без отложенной записи; close не выпускает байты после отказа."""
    def __init__(сам, поток, сверить, *, текстовый=False, кодировка='utf-8', ошибки='strict'):
        сам._поток, сам._сверить = поток, сверить
        сам._текстовый, сам.encoding, сам.errors = текстовый, кодировка, ошибки

    def write(сам, данные):
        if сам._текстовый:
            if type(данные) is not str:
                raise TypeError('текстовый выход требует строку')
            сырые = данные.encode(сам.encoding, сам.errors)
        else:
            сырые = bytes(данные)
        позиция = 0
        while позиция < len(сырые):
            сам._сверить()
            число = сам._поток.write(сырые[позиция:])
            if type(число) is not int or число <= 0:
                raise OSError('неполная безбуферная запись')
            позиция += число
        return len(данные)

    def writelines(сам, строки):
        for строка in строки:
            сам.write(строка)

    def truncate(сам, *аргументы):
        сам._сверить()
        return сам._поток.truncate(*аргументы)

    def flush(сам):
        сам._сверить()
        return сам._поток.flush()

    def close(сам):
        # Подлежащий FileIO изначально открыт с buffering=0.
        return сам._поток.close()

    @property
    def buffer(сам):
        return ОхраняемыйФайл(сам._поток, сам._сверить)

    def __getattr__(сам, имя):
        return getattr(сам._поток, имя)

    def __enter__(сам):
        return сам

    def __exit__(сам, *ошибка):
        сам.close()


class ВременноеПредставление:
    """Одна явно выбранная пустая область для точных Markdown-данных H."""
    def __init__(сам, контекст):
        сам.контекст = контекст; сам.name = str(контекст.представление)

    def __enter__(сам):
        к = сам.контекст; к.сверить()
        требовать(not к.представление_активно and not any(к.представление.iterdir()),
            'представление H занято; автоматический повтор запрещён')
        к.представление_активно = True
        try:
            д = os.open(к.маркер_представления, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
            try:
                с = os.fstat(д); сам.маркер = (с.st_dev, с.st_ino)
                к.метка_маркера = к.идентичности.метка(к.маркер_представления)
            finally:
                os.close(д)
        except BaseException:
            к.представление_активно = False
            raise
        return сам.name

    def __exit__(сам, *ошибка):
        к = сам.контекст; к.сверить()
        с = к.маркер_представления.lstat()
        требовать((с.st_dev, с.st_ino) == сам.маркер, 'подменён маркер представления H')
        пути = list(к.представление.rglob('*'))
        for путь in пути:
            требовать(not путь.is_symlink() and (
                путь.is_dir() and путь in к.каталоги_представления or
                путь.is_file() and путь in к.файлы_представления | {к.маркер_представления}),
                'неизвестный материал в представлении H')
        for путь in sorted(пути, key=lambda п: (len(п.parts), str(п)), reverse=True):
            if путь == к.маркер_представления: continue
            путь.rmdir() if путь.is_dir() else путь.unlink()
        к.маркер_представления.unlink()
        к.представление_активно = False
        к.метка_маркера = None



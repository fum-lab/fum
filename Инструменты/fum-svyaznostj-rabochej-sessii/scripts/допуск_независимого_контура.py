    def исполнить(сам):
        сам.диагностика.событие('D-начало')
        сам.допустить_зависимости()
        сам.диагностика.событие('D-конец')
        def читающая_свежесть(корень, *, проверка=None):
            if проверка is not None:
                принятый = importlib.import_module('связность_независимого_журнала')
                требовать(проверка is принятый.проверить_полную_свежесть,
                    'невыбранный callback полной свежести')
                return проверка(корень)
            свежесть = importlib.import_module('свежесть_подготовки_этапа')
            результат = свежесть.update_repository(Path(корень), check=True)
            return ['md recency check failed: ' + э for э in результат.errors]
        этап = сам.аргументы.этап

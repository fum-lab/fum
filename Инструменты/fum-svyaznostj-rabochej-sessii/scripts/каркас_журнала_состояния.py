"""Чистый каркас P.2 с отдельной незавершённой рабочей областью отчёта."""
import независимая_пара_журнала as пара

контракт = пара.контракт
ОТЧЁТ = 'План повторного этапа. Установка пары и выполнение поручения не произведены.\n'


def рассчитать(п):
    снимки = {}
    for источник in п['источники_команд']:
        граница = источник['граница_снимка']
        for номер in источник['экземпляры']:
            снимки[номер] = {'sha256': граница['sha256'], 'байты': граница['граница']}
    команды = [{**к, 'снимок': снимки[к['экземпляр']], 'sha256_текста': контракт.хэш(к['текст'].encode())}
        for к in п['команды']]
    вход = {'схема': 'fum.независимая-пара-журнала.1', 'узел': п['узел'],
        'корневая_задача': п['координатор'], 'писатель': п['владелец'],
        'основание': п['доверие']['источник'], 'журнал': п['журнал'], 'заголовок': п['заголовок'],
        'первоначальный_запрос': п['первоначальный_запрос'], 'предыдущий_этап': п['предыдущий_этап'],
        'команды': команды, 'отчёт': {'текст': ОТЧЁТ, 'sha256': контракт.хэш(ОТЧЁТ.encode())}}
    итог = пара.построить_пару(вход)
    блок = {'схема': 'fum.план-рабочей-области-отчёта-состояния.1',
        'этап': итог['идентификатор'], 'исходный_коммит': п['исходный_коммит'],
        'ожидания': п['доверие']['источник'], 'выполнение': 'не-начато', 'запуски': [],
        'разрешение_установки': False}
    записи = []
    for файл in итог['файлы']:
        данные = файл['байты']
        if файл['путь'].endswith('/отчёт.md'):
            текст = данные.decode().rsplit('\n<!-- FUM-MD-RECENCY:BEGIN -->\n', 1)[0]
            текст += ('\n<!-- FUM-СОСТОЯНИЕ-ЭТАП:BEGIN -->\n'
                '<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->\n```json\n' + контракт.канон(блок).decode()
                + '\n```\n<!-- FUM-СОСТОЯНИЕ-ЭТАП:END -->\n\n'
                '## Прямые запуски проверок\n\n'
                '<!-- FUM-CHECK-RUNS:BEGIN состояние=открыт; каталог=материалы/запуски-проверок -->\n'
                '<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->\n'
                'Запусков ещё нет.\n<!-- FUM-CHECK-RUNS:END -->\n')
            данные = контракт.свежесть(текст, контракт.имя_журнала(п['журнал']))
        записи.append({'путь': файл['путь'], 'текст': данные.decode(),
            'sha256': контракт.хэш(данные), 'режим': файл['режим']})
    контракт.требовать(sum(len(ф['текст'].encode()) for ф in записи) <= контракт.ПРЕДЕЛ_ПАРЫ,
        'пара превышает границу')
    return итог['идентификатор'], записи

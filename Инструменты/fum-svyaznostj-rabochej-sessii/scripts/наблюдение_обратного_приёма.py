"""Чтение Git для обратного приёма; ни ревью, ни разрешения записи не выдаёт."""
import hashlib
import os
from pathlib import Path
import subprocess

from контракт_обратного_приёма import _ветка


def _требовать(условие, сообщение):
    if not условие:
        raise ValueError(сообщение)


def _гит(корень, *аргументы):
    среда = {ключ: значение for ключ, значение in os.environ.items()
             if not ключ.startswith("GIT_") or ключ in {"GIT_CONFIG_GLOBAL", "GIT_CONFIG_NOSYSTEM"}}
    среда.update(GIT_NO_REPLACE_OBJECTS="1", GIT_OPTIONAL_LOCKS="0", GIT_NO_LAZY_FETCH="1")
    процесс = subprocess.run(["git", "--no-replace-objects", "--no-optional-locks",
                              "-c", "core.fsmonitor=false", "-C", str(корень), *аргументы],
                             env=среда, capture_output=True, timeout=120)
    _требовать(процесс.returncode == 0, "Git не подтвердил чтение: " + аргументы[0])
    return процесс.stdout


def _текст(корень, *аргументы):
    return _гит(корень, *аргументы).decode("utf-8").strip()


def _адрес_гит(корень, имя):
    return Path(_текст(корень, "rev-parse", "--path-format=absolute", "--git-path", имя))


def _ветки(корень, получатель, источник):
    _требовать(_текст(корень, "symbolic-ref", "HEAD") == получатель["ветка"],
              "Рабочее дерево не принадлежит получателю")
    _требовать(_текст(корень, "rev-parse", "HEAD") == получатель["коммит"],
              "Изменился HEAD получателя")
    for имя, выбранная in (("получатель", получатель), ("источник", источник)):
        _требовать(_текст(корень, "rev-parse", "--verify", выбранная["ветка"]) == выбранная["коммит"],
                  "Изменился " + имя)
        _требовать(_гит(корень, "cat-file", "-t", выбранная["коммит"]) == b"commit\n",
                  "Выбранный объект не является коммитом: " + имя)
        _требовать(_текст(корень, "rev-parse", выбранная["коммит"] + "^{tree}") == выбранная["дерево"],
                  "Не совпало дерево: " + имя)


def _без_внешних_фильтров(корень):
    конфигурация = _гит(корень, "config", "--null", "--list")
    _требовать(not any(строка.partition(b"\n")[0].lower().startswith(b"filter.")
                       for строка in конфигурация.split(b"\0")),
              "Внешний фильтр не поддержан при чтении состояния")
    for запись in _гит(корень, "ls-files", "--stage", "-z").split(b"\0"):
        if not запись:
            continue
        поля, путь = запись.split(b"\t", 1)
        режим, _, стадия = поля.split()
        if режим != b"160000" or стадия != b"0":
            continue
        вложенный = корень / os.fsdecode(путь)
        _требовать(вложенный.resolve() == вложенный and вложенный.is_relative_to(корень)
                  and вложенный != корень, "Необычный путь Git-зависимости")
        if not os.path.lexists(вложенный / ".git"):
            continue
        _требовать(_текст(вложенный, "rev-parse", "--show-toplevel") == str(вложенный),
                  "Чужой корень Git-зависимости")
        _без_внешних_фильтров(вложенный)


def _рабочее_состояние(корень):
    _требовать(not os.path.lexists(_адрес_гит(корень, "info/grafts")),
              "Подмена истории через info/grafts не поддержана")
    for имя in ("MERGE_HEAD", "CHERRY_PICK_HEAD", "REVERT_HEAD", "rebase-merge",
                "rebase-apply", "sequencer", "BISECT_LOG"):
        _требовать(not os.path.lexists(_адрес_гит(корень, имя)),
                  "Незавершённая операция Git: " + имя)
    флаги = _гит(корень, "ls-files", "-v", "-z").split(b"\0")
    _требовать(all(not строка or строка.startswith(b"H ") for строка in флаги),
              "Неподдержанные флаги индекса скрывают состояние файлов")
    _без_внешних_фильтров(корень)
    _требовать(_гит(корень, "status", "--porcelain=v1", "-z", "--untracked-files=all",
                       "--ignore-submodules=none") == b"", "Рабочее дерево нечисто")
    индекс = _адрес_гит(корень, "index")
    _требовать(not индекс.is_symlink() and индекс.is_file(), "Необычный файл индекса")
    return hashlib.sha256(индекс.read_bytes()).hexdigest()


def снять_состояние(корень, получатель, источник):
    """Две сверки границ чтения при одном писателе; не атомарный снимок ОС.

    Чистота соответствует Git status. Подлинность и качество ревью, полная
    побайтовая ревизия рабочей копии и переносимость тестов сюда не входят.
    """
    корень = Path(корень)
    _требовать(корень.is_absolute() and корень.resolve(strict=True) == корень,
              "Нужен физический абсолютный корень")
    _ветка(получатель, "получатель")
    _ветка(источник, "источник")
    _требовать(получатель["ветка"] != источник["ветка"]
              and получатель["коммит"] != источник["коммит"], "Нужны разные ветки и коммиты")
    _требовать(получатель["ветка"] != "refs/heads/master", "Специальный маршрут master не поддержан")
    _требовать(_текст(корень, "rev-parse", "--show-toplevel") == str(корень), "Чужой корень Git")
    _ветки(корень, получатель, источник)
    индекс = _рабочее_состояние(корень)
    try:
        _гит(корень, "merge-base", "--is-ancestor", получатель["коммит"], источник["коммит"])
    except ValueError as ошибка:
        raise ValueError("Основа не подтверждена предком кандидата") from ошибка
    разница = _гит(корень, "diff", "--raw", "-z", "--no-abbrev", "--no-ext-diff", "--no-textconv",
                   "--no-renames", "--no-color", "--ignore-submodules=none", "--no-relative",
                   "-O", os.devnull,
                   получатель["коммит"], источник["коммит"], "--")
    _ветки(корень, получатель, источник)
    _требовать(_рабочее_состояние(корень) == индекс, "Индекс изменился во время чтения")
    _ветки(корень, получатель, источник)
    return {"схема": "fum.состояние-git-обратного-приёма.1",
            "корень_sha256": hashlib.sha256(os.fsencode(корень)).hexdigest(),
            "получатель": dict(получатель), "источник": dict(источник),
            "основа_является_предком": True, "индекс_sha256": индекс,
            "формат_разницы": "git-raw-z-v1",
            "разница_sha256": hashlib.sha256(разница).hexdigest(),
            "разрешение_записи": False}

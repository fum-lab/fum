def прочитать_гит(корень, *аргументы):
    """Прежняя RO-граница; fsmonitor/hooks не получают побочного запуска."""
    среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_NO_LAZY_FETCH='1', GIT_OPTIONAL_LOCKS='0')
    процесс = subprocess.run(['git', '--no-optional-locks', '--no-replace-objects', '--no-lazy-fetch',
        '-c', 'trace2.normalTarget=0', '-c', 'trace2.eventTarget=0', '-c', 'trace2.perfTarget=0',
        '-c', 'core.fsmonitor=false', '-c', 'core.hooksPath='+os.devnull, '-c', 'submodule.recurse=false',
        '-C', str(корень), *аргументы], stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, env=среда, timeout=30)
    требовать(процесс.returncode==0, 'чтение Git отказало')
    return процесс.stdout


def полный_реф(значение):
    строка(значение)
    требовать(значение.startswith('refs/heads/') and len(значение)>11
        and not any(знак in значение for знак in ('..', '@{', '\\', '//'))
        and not any(ord(знак)<33 or ord(знак) in (127, 126, 94, 58, 63, 42, 91) for знак in значение)
        and not any(часть.startswith('.') or часть.endswith(('.', '.lock')) for часть in значение.split('/')),
        'нужен полный буквальный ref ветки')


def список(значение, проверка, *, непустой=True):
    требовать(type(значение) is list and (значение or not непустой), 'нужен список')
    for элемент in значение:
        проверка(элемент)
    требовать(len(значение)==len(set(значение)), 'повтор элемента списка')


def относительный(имя):
    строка(имя); путь = Path(имя)
    требовать(not путь.is_absolute() and путь.as_posix()==имя
        and not any(часть in ('.', '..', '.git') for часть in путь.parts)
        and unicodedata.normalize('NFC', имя)==имя, 'неточный относительный путь')


def приватный(имя):
    путь = чтение.физический(имя)
    требовать(not any(os.path.lexists(предок / '.git') for предок in путь.parents),
        'приватный вход внутри Git')
    return путь



"""Закрытая доставка expected: сохранённые OID и реестр, без live-деревьев."""
from pathlib import PurePosixPath
import re

import восстановление_прерванной_задачи as канон
import доставка_план as доставка
import доставка_гит as гит


def прочитать_источник(корень, выбор):
    канон.поля(выбор, {'коммит', 'путь', 'sha256'})
    гит.полный_объект(корень, выбор['коммит']); канон.полный_хэш(выбор['sha256'])
    канон.обычное_поручение.история.точный_путь(выбор['путь'])
    размер = int(гит.гит(корень, 'cat-file', '-s', выбор['коммит']+':'+выбор['путь']))
    канон.требовать(0 < размер <= 64*1024*1024, 'исторический источник превышает границу')
    данные = гит.объект_файла(корень, выбор['коммит'], выбор['путь'])
    канон.требовать(len(данные) == размер and канон.хэш(данные) == выбор['sha256'],
        'подмена исторического источника')
    return данные


def _участник(запись, назначение, корень):
    канон.идентичность(запись['владелец'])
    адрес = запись['корень']; канон.строка(адрес)
    канон.требовать(PurePosixPath(адрес).is_absolute()
        and str(PurePosixPath(адрес)) == адрес and '..' not in PurePosixPath(адрес).parts,
        'неверный сохранённый корень доставки')
    ветка = запись['ref']; канон.строка(ветка)
    гит.выполнить(корень, 'check-ref-format', ветка)
    if ветка == 'refs/heads/fuma':
        канон.требовать((адрес, запись['владелец'], ветка) ==
            (назначение['корень'], назначение['владелец'], назначение['ref']), 'чужое назначение fuma')
    else:
        # У старого плана .2 нет отдельного выбора A для state-получателя.
        канон.требовать(ветка.startswith('refs/heads/codex/'), 'неподдержанный исторический ref доставки')


def проверить(значение, *, корень, координатор, задача, идентификатор):
    канон.поля(значение, {'план', 'владельцы'})
    план, владельцы = значение['план'], значение['владельцы']
    канон.поля(план, {'схема', 'источник', 'владельцы_sha256', 'получатели', 'идентификатор', 'назначение'})
    канон.требовать(план['схема'] == 'fum.план-обратной-доставки.2'
        and план['идентификатор'] == идентификатор == доставка.хэш({к: з for к, з in план.items()
            if к != 'идентификатор'}), 'неверный исторический план доставки')
    назначение = гит.проверить_назначение(план['назначение'])
    канон.требовать(назначение['корневая_задача'] == координатор, 'чужой ROOT доставки')
    канон.требовать(type(владельцы) is dict and владельцы
        and доставка.хэш(владельцы) == план['владельцы_sha256'], 'подмена исторического реестра')
    ветки = []
    for адрес, запись in владельцы.items():
        канон.требовать(type(запись) is dict, 'неверная запись владельца')
        канон.поля(запись, {'задача', 'ref', 'корневая_задача'} if запись.get('ref') == 'refs/heads/fuma'
            else {'задача', 'ref'})
        if запись['ref'] == 'refs/heads/fuma':
            канон.требовать(запись['корневая_задача'] == координатор, 'чужое назначение реестра')
        _участник({'корень': адрес, 'владелец': запись['задача'], 'ref': запись['ref']}, назначение, корень)
        ветки.append(запись['ref'])
    канон.требовать(len(set(ветки)) == len(ветки), 'повтор владельца ветки')
    источник = план['источник']
    канон.поля(источник, {'корень', 'ref', 'коммит', 'владелец', 'срез', 'приёмка', 'дерево',
        'решение', 'полная_приёмка', 'версия'})
    канон.поля(источник['приёмка'], {'путь', 'sha256'})
    приёмка = канон.разобрать(прочитать_источник(корень, {'коммит': источник['коммит'], **источник['приёмка']}))
    канон.поля(приёмка, {'схема', 'коммит', 'дерево', 'проверяющий', 'состояние', 'граница', 'свидетельства'})
    канон.требовать(type(приёмка['свидетельства']) is list and приёмка['свидетельства'], 'нет свидетельств приёмки')
    for выбор in приёмка['свидетельства']:
        канон.поля(выбор, {'путь', 'sha256'})
        прочитать_источник(корень, {'коммит': источник['коммит'], **выбор})
    факты = доставка.прочитать_приёмку(корень, источник['коммит'], источник['срез'], источник['приёмка'])
    канон.требовать(источник['полная_приёмка'] is False
        and all(источник[к] == з for к, з in факты.items()), 'подмена сохранённой приёмки')
    получатели = план['получатели']
    канон.требовать(type(получатели) is list and получатели, 'пустая историческая доставка')
    порядок = []
    for цель in получатели:
        канон.поля(цель, {'корень', 'владелец', 'ref', 'коммит', 'дерево', 'отношение', 'патчи',
            'причина', 'зависимость', 'сигнал_недоставки', 'подтверждение'})
        for имя in ('коммит', 'дерево'):
            канон.требовать(type(цель[имя]) is str and re.fullmatch(r'(?:[0-9a-f]{40}|[0-9a-f]{64})', цель[имя]),
                'неверный OID исторической доставки')
        гит.полный_объект(корень, цель['коммит'])
        канон.требовать(гит.гит(корень, 'rev-parse', цель['коммит']+'^{tree}') == цель['дерево'],
            'подмена дерева получателя')
        отношение, патчи = доставка.отношение(корень, источник['срез'], цель['коммит'])
        канон.требовать(цель['отношение'] == отношение and цель['патчи'] == патчи
            and type(цель['сигнал_недоставки']) is bool
            and цель['сигнал_недоставки'] == (отношение not in ('в предках', 'равное дерево')),
            'подмена исторического отношения')
        for имя in ('причина', 'зависимость'): канон.строка(цель[имя])
        канон.требовать(цель['подтверждение'] == 'unknown', 'неверная граница исторической доставки')
        порядок.append((цель['ref'], цель['владелец'], цель['корень']))
    канон.требовать(порядок == sorted(set(порядок)) and len({э[0] for э in порядок}) == len(порядок)
        and len({э[2] for э in порядок}) == len(порядок), 'повтор или порядок исторических получателей')
    for участник in [источник, *получатели]:
        _участник(участник, назначение, корень)
        запись = владельцы.get(участник['корень'])
        канон.требовать(type(запись) is dict and запись['задача'] == участник['владелец']
            and запись['ref'] == участник['ref'], 'участник не связан с историческим реестром')
    канон.требовать(any(ц['владелец'] == задача for ц in получатели)
        and any(ц['ref'] == 'refs/heads/fuma' for ц in [источник, *получатели]),
        'план не связан с исполнителем и fuma')
    return план

"""Чистое решение о фиксации объявленного готового этапа, без выполнения Git."""
import copy
import re
import uuid


ПОЛЯ_СНИМКА = frozenset({"задача", "ветка", "исходный_коммит", "запрос", "разрешённые_цели",
                        "экземпляры", "отпечаток_содержимого", "проверки"})
ПОЛЯ_ГОТОВНОСТИ = frozenset({"схема", "снимок", "готов_в_наносекундах_эпохи", "предел_секунд"})


def требовать(условие, пояснение):
    if not условие:
        raise ValueError(пояснение)


def целое(значение):
    return type(значение) is int and значение >= 0


def точный_идентификатор(значение):
    try:
        return isinstance(значение, str) and str(uuid.UUID(значение)) == значение
    except ValueError:
        return False


def точный_хэш(значение):
    return isinstance(значение, str) and re.fullmatch(r"[0-9a-f]{64}", значение) is not None


def относительный_путь(значение):
    return (isinstance(значение, str) and bool(значение)
            and not any(ord(знак) < 32 or знак in "\\:" for знак in значение)
            and all(часть.casefold() not in ("", ".", "..", ".git") for часть in значение.split("/")))


def список(значения, проверка, пустой=False):
    требовать(isinstance(значения, list) and (пустой or bool(значения)), "нужен явный список")
    требовать(all(проверка(значение) for значение in значения), "некорректное значение списка")
    требовать(len(set(значения)) == len(значения), "повтор значения списка")


def проверить_снимок(снимок):
    требовать(isinstance(снимок, dict) and set(снимок) == ПОЛЯ_СНИМКА, "неверный состав снимка")
    требовать(точный_идентификатор(снимок["задача"]), "нужен корневой UUID")
    ветка = снимок["ветка"]
    требовать(isinstance(ветка, str) and ветка.startswith("refs/heads/") and len(ветка) > 11
              and not any(знак.isspace() or ord(знак) < 32 for знак in ветка), "нужен полный ref")
    требовать(isinstance(снимок["исходный_коммит"], str)
              and re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", снимок["исходный_коммит"]) is not None, "нужен полный OID")
    требовать(относительный_путь(снимок["запрос"]), "нужен относительный путь запроса")
    список(снимок["разрешённые_цели"], относительный_путь)
    список(снимок["экземпляры"], точный_хэш)
    список(снимок["проверки"], точный_идентификатор)
    требовать(точный_хэш(снимок["отпечаток_содержимого"]), "нужен отпечаток содержимого")


def проверить_готовность(запись):
    требовать(isinstance(запись, dict) and set(запись) == ПОЛЯ_ГОТОВНОСТИ, "неверные поля готовности")
    требовать(запись["схема"] == "fum.граница-готового-этапа.1", "неверная схема готовности")
    проверить_снимок(запись["снимок"])
    требовать(целое(запись["готов_в_наносекундах_эпохи"]), "неверное время готовности")
    требовать(целое(запись["предел_секунд"]) and запись["предел_секунд"] > 0, "неверный предел ожидания")


def объявить(снимок, сейчас, предел_секунд, прежняя=None):
    """Объявление не проверяет Git и не заменяет предкоммитный допуск."""
    запись = {"схема": "fum.граница-готового-этапа.1", "снимок": copy.deepcopy(снимок),
              "готов_в_наносекундах_эпохи": сейчас, "предел_секунд": предел_секунд}
    проверить_готовность(запись)
    if прежняя is not None:
        проверить_готовность(прежняя)
        требовать(прежняя["снимок"] == снимок and прежняя["предел_секунд"] == предел_секунд,
                  "границу готового этапа нельзя расширить или изменить повтором")
        требовать(сейчас >= прежняя["готов_в_наносекундах_эпохи"], "часы раньше объявления готовности")
        return copy.deepcopy(прежняя)
    return запись


def оценить(запись, снимок, поздние_экземпляры, сейчас, остановлено=False, минимальный_возраст=0):
    проверить_готовность(запись)
    проверить_снимок(снимок)
    список(поздние_экземпляры, точный_хэш, пустой=True)
    требовать(type(остановлено) is bool, "остановка должна быть явным логическим значением")
    требовать(целое(сейчас) and сейчас >= запись["готов_в_наносекундах_эпохи"], "часы раньше объявления готовности")
    требовать(целое(минимальный_возраст), "неверный прежний возраст")
    возраст = max(минимальный_возраст, сейчас - запись["готов_в_наносекундах_эпохи"])
    действие = ("остановиться" if остановлено else
                "зафиксировать-этап" if запись["снимок"] == снимок else "повторно-проверить-этап")
    принятые = set(запись["снимок"]["экземпляры"])
    return {"схема": "fum.контроль-фиксации-этапа.1", "действие": действие,
            "возраст_наносекунды": возраст, "задержка": возраст >= запись["предел_секунд"] * 1_000_000_000,
            "фиксировать_этап": действие == "зафиксировать-этап", "начинать_следующий_этап": False,
            "следующий_этап": [элемент for элемент in поздние_экземпляры if элемент not in принятые]}

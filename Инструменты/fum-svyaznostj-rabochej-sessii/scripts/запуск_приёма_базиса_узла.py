def _снимок_живого_источника(источник, предел_нс):
    путь = физический(источник['путь']); до = отпечаток(путь.lstat())
    размер = до[6]
    требовать(источник['конец']['граница'] <= размер <= 32*1024*1024*1024,
        'живой источник усечён или превышает прежний бюджет')
    дескриптор = os.open(путь, os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    try:
        требовать(отпечаток(os.fstat(дескриптор)) == до, 'живой источник заменён при открытии')
        требовать(os.pread(дескриптор, 1, размер-1) == b'\n', 'неполная живая нативная строка')
        позиция = 0; вычисленный = hashlib.sha256()
        while позиция < размер:
            требовать(time.perf_counter_ns() < предел_нс, 'превышен общий бюджет живого приёма')
            блок = os.pread(дескриптор, min(1024*1024, размер-позиция), позиция)
            требовать(bool(блок), 'живой источник усечён во время снимка')
            позиция += len(блок); вычисленный.update(блок)
        требовать(отпечаток(os.fstat(дескриптор)) == отпечаток(путь.lstat()) == до,
            'живой источник изменился во время снимка')
        return dict(источник, конец={'граница':размер, 'sha256':вычисленный.hexdigest()})
    finally:
        os.close(дескриптор)



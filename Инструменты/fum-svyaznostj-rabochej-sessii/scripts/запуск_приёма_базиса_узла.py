def физический(значение, *, каталог=False):
    требовать(type(значение) is str and Path(значение).is_absolute(), 'нужен абсолютный физический путь')
    путь = Path(значение)
    требовать(str(путь) == значение and путь == путь.resolve(strict=True), 'алиас физического пути запрещён')
    предок = Path(путь.anchor)
    for часть in путь.parts[1:]:
        требовать(часть in os.listdir(предок), 'нет точного регистра физического пути')
        предок /= часть
        состояние = предок.lstat()
        требовать(not stat.S_ISLNK(состояние.st_mode), 'symlink физического источника запрещён')
    требовать((stat.S_ISDIR if каталог else stat.S_ISREG)(состояние.st_mode), 'неверный тип физического источника')
    return путь


def отпечаток(состояние):
    return tuple(getattr(состояние, к) for к in ('st_dev', 'st_ino', 'st_mode',
        'st_uid', 'st_gid', 'st_nlink', 'st_size', 'st_mtime_ns', 'st_ctime_ns'))


def прочитать_приватный(путь):
    путь = физический(str(путь))
    до = путь.lstat()
    требовать(до.st_uid == os.getuid() and до.st_nlink == 1
        and stat.S_IMODE(до.st_mode) == 0o400, 'приватная копия должна быть собственной, неизменяемой и mode0400')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        с = os.fstat(дескриптор)
        требовать(отпечаток(с) == отпечаток(до), 'физический источник заменён перед чтением')
        with os.fdopen(дескриптор, 'rb', closefd=False) as поток:
            данные = поток.read(ПРЕДЕЛ_ИСТОЧНИКА + 1)
        требовать(0 < len(данные) <= ПРЕДЕЛ_ИСТОЧНИКА
            and отпечаток(os.fstat(дескриптор)) == отпечаток(до)
            and отпечаток(путь.lstat()) == отпечаток(до), 'физический источник изменился во время чтения')
    finally:
        os.close(дескриптор)
    return данные


def проверить_импорты(данные):
    разрешены = {'ast', 'hashlib', 'json', 'os', 'datetime', 'pathlib', 'posixpath',
        're', 'select', 'shutil', 'stat', 'subprocess', 'time', 'types', 'unicodedata',
        'uuid', 'argparse', 'sys', 'base64', 'fcntl', 'html', 'tempfile'}
    for узел in ast.walk(ast.parse(данные.decode('utf-8'))):
        if isinstance(узел, ast.Import):
            требовать(all(э.name in разрешены for э in узел.names), 'контур имеет внешнюю Python-зависимость')
        elif isinstance(узел, ast.ImportFrom):
            требовать(узел.level == 0 and узел.module in разрешены, 'контур имеет проектный или относительный импорт')
        elif isinstance(узел, ast.Call) and isinstance(узел.func, ast.Name):
            требовать(узел.func.id != '__import__', 'динамический импорт контура запрещён')


def загрузить_контур(корень, каталог, описание, *, читатель=None):
    """Только чтение; ROOT должен заранее независимо принять BOOT и выбрать описание."""
    if читатель is None:
        with НачальныеОбъекты(корень) as собственный:
            return загрузить_контур(корень, каталог, описание, читатель=собственный)
    проверить_контур(описание)
    корень = физический(str(корень), каталог=True); каталог = физический(str(каталог), каталог=True)
    требовать(корень != каталог and корень not in каталог.parents and каталог not in корень.parents,
        'Q и W должны быть внешними друг другу')
    состояние = каталог.lstat()
    требовать(состояние.st_uid == os.getuid() and stat.S_IMODE(состояние.st_mode) == 0o700,
        'Q должен быть собственным mode0700')
    исходники = {}
    for запись in описание['файлы']:
        требовать(точный_файл(корень, описание['K'], запись['путь'], читатель=читатель)
            == ('100644', 'blob', запись['blob']), 'файл контура не принадлежит точному K')
        данные = объект(корень, запись['blob'], 'blob', читатель=читатель)
        требовать(len(данные) == запись['байты'] and хэш(данные) == запись['sha256'],
            'подменён исполняемый blob контура')
        требовать(прочитать_приватный(каталог / запись['путь']) == данные,
            'физические исполняемые байты Q не совпали с K')
        проверить_импорты(данные); исходники[запись['путь']] = данные
    читатель.проверить_срок()
    модуль = types.ModuleType('_fum_закреплённый_базис')
    модуль.__file__ = описание['K'] + ':' + СЫРОЙ_МОДУЛЬ
    код = compile(исходники[СЫРОЙ_МОДУЛЬ], модуль.__file__, 'exec')
    читатель.проверить_срок()
    exec(код, модуль.__dict__)
    with модуль.ПакетСырыхОбъектов(корень) as читатель:
        граф = модуль.замкнуть_историю(читатель, (описание['K'],))
        таблица = модуль.сырая_таблица(читатель, граф[описание['K']]['дерево'])
        модуль.коллизии([таблица])
        for запись in описание['файлы']:
            требовать(таблица.get(запись['путь']) == ('100644', 'blob', запись['blob']),
                'файл контура не принадлежит точному K')
    return модуль


def проверить(корень, каталог, выбранный_контур, выбранная_приёмка, выбранный_акт):
    """Полная читающая сверка; возвращаемый результат не разрешает отложенный FF."""
    корень = физический(str(корень), каталог=True)
    with НачальныеОбъекты(корень) as начальный:
        описание = разобрать(прочитать_источник(корень, выбранный_контур, читатель=начальный))
        проверить_контур(описание)
        приёмка = разобрать(прочитать_источник(корень, выбранная_приёмка, читатель=начальный))
        проверить_приёмку(приёмка)
        требовать(приёмка['контур'] == выбранный_контур
            and приёмка['приёмка_состава']['состав']['K'] == описание['K']
            and приёмка['хэш_корня'] == хэш(str(корень).encode()), 'приёмка выбрала другой K или W')
        акт = разобрать(прочитать_источник(корень, выбранный_акт, читатель=начальный))
        сверить_акт(акт, приёмка, выбранная_приёмка)
        состояние = приёмка['приёмка_состава']['состав']
        источники = (выбранный_контур, выбранная_приёмка, выбранный_акт)
        проверить_начальную_историю(корень, состояние, источники, читатель=начальный)
        модуль = загрузить_контур(корень, каталог, описание, читатель=начальный)
    модуль.корень_гит(корень)
    with модуль.ПакетСырыхОбъектов(корень) as читатель:
        источники = (выбранный_контур, выбранная_приёмка, выбранный_акт)
        граф = модуль.замкнуть_историю(читатель, tuple(э['коммит'] for э in источники))
        for выбранный in источники:
            таблица = модуль.сырая_таблица(читатель, граф[выбранный['коммит']]['дерево'])
            модуль.коллизии([таблица])
            запись = таблица.get(выбранный['путь'])
            требовать(запись is not None and запись[:2] == ('100644', 'blob'),
                'сырой источник приёмки отсутствует или имеет неверный тип')
            данные = читатель.прочитать(запись[2], 'blob', сохранить=True)
            требовать(хэш(данные) == выбранный['sha256'], 'сырая история приёмки изменилась')
    состав = модуль.состав_базиса(корень, состояние['R'], состояние['B'], состояние['K'])
    модуль.сверить_состав(состав, приёмка['приёмка_состава'])
    первый = приёмка['первый_цикл']
    защищённые = модуль.сверить_первый_цикл(корень, состояние['R'], состояние['B'],
        первый['акт'], первый['полномочия'], первый['идентичность'], первый['защищённые'])
    первые_полномочия = разобрать(прочитать_источник(корень, первый['полномочия']))
    требовать(первые_полномочия['хэш_корня'] == приёмка['хэш_корня']
        and первые_полномочия['ветка'] == приёмка['ветка'], 'первый цикл принадлежит другому W/ref')
    семантика = модуль.семантика_базиса(корень, состояние['B'])
    сверить_результаты(приёмка, состав, семантика, защищённые)
    return {'схема': 'fum.сверка-приёма-базиса-узла.1', 'состав': состав,
        'семантика': семантика, 'защищённые': защищённые,
        'приёмка': выбранная_приёмка, 'акт': выбранный_акт, 'контур': выбранный_контур}


def временная_метка_UTC(т):
    требовать(type(т) is str and re.fullmatch(
        r'[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]{1,9})?Z', т),
        'неверная первичная временная метка UTC')
    try:
        datetime.datetime.fromisoformat(т)
    except ValueError as ошибка:
        raise ValueError('невозможная первичная временная метка') from ошибка
    return т


def нативная_строка(данные):
    требовать(type(данные) is bytes and данные.endswith(b'\n')
        and данные.count(b'\n') == 1 and b'\r' not in данные,
        'нужна одна завершённая первичная строка LF')
    запись = разобрать_JSON(данные, ПРЕДЕЛ_НАТИВНОЙ_СТРОКИ)
    обязательные = {'type', 'payload', 'timestamp', 'ordinal'}
    требовать(type(запись) is dict and обязательные <= set(запись)
        <= обязательные | {'metadata'}, 'неизвестная первичная рамка')
    требовать(type(запись['type']) is str and запись['type'] in
        ('session_meta','turn_context','response_item','event_msg','compacted',
         'token_usage_record','inter_agent_communication_metadata','world_state'),
        'неизвестный первичный тип')
    временная_метка_UTC(запись['timestamp'])
    требовать(type(запись['ordinal']) is int and запись['ordinal'] >= 0
        and type(запись['payload']) is dict, 'неверные поля первичной рамки')
    if 'metadata' in запись:
        мета = запись['metadata']
        требовать(type(мета) is dict and мета.get('client_authored') is False,
            'нет первичного происхождения транспортной рамки')
        требовать(set(мета) <= {'client_authored', 'fallback_token_limit_override',
            'user_input_order', 'sender_user_messages', 'retained_source', 'mcp_attribution'},
            'неизвестные аннотации первичной рамки')
        for ключ, минимум in [('fallback_token_limit_override',1),('user_input_order',0)]:
            if ключ in мета:
                требовать(type(мета[ключ]) is int and мета[ключ] >= минимум,
                    'неверный тип аннотации первичной рамки')
        if 'sender_user_messages' in мета:
            цитаты = мета['sender_user_messages']
            поля(цитаты, {'receiver_turn_id','receiver_message_id','text'})
            идентификатор(цитаты['receiver_turn_id'])
            требовать(type(цитаты['receiver_message_id']) is str and цитаты['receiver_message_id']
                and type(цитаты['text']) is str, 'неверные аннотации цитат отправителя')
        if 'retained_source' in мета:
            источник = мета['retained_source']; поля(источник, {'complete','revision','id'})
            требовать(источник['complete'] is True and type(источник['revision']) is str,
                'неполная аннотация сохранённого источника')
            поля(источник['id'], {'message_id','role','turn_id'})
            идентификатор(источник['id']['turn_id'])
            требовать(источник['id']['role'] in ('assistant','user')
                and type(источник['id']['message_id']) is str and источник['id']['message_id'],
                'неверное происхождение сохранённого источника')
        if 'mcp_attribution' in мета:
            атрибуция=мета['mcp_attribution']
            требовать(type(атрибуция) is dict, 'неизвестная MCP-атрибуция')
            if атрибуция.get('status')=='none':
                поля(атрибуция, {'status'})
            else:
                if атрибуция.get('status')=='attribution_error':
                    поля(атрибуция, {'status','error_reason','sources'})
                    требовать(атрибуция['error_reason']=='restored_error_unknown',
                        'неизвестная версия ошибки MCP-атрибуции')
                else:
                    поля(атрибуция, {'status','sources'})
                    требовать(атрибуция['status']=='complete', 'неизвестный статус MCP-атрибуции')
                требовать(type(атрибуция['sources']) is list
                    and 0 < len(атрибуция['sources']) <= 256, 'неполная MCP-атрибуция')

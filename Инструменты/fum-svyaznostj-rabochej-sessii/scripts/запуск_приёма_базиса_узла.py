def _сырой_результат_приёма(корень, идентификатор_коммита):
    данные = объект(корень, идентификатор_коммита, 'commit')
    требовать(hashlib.sha1(b'commit '+str(len(данные)).encode()+b'\0'+данные).hexdigest()
        == идентификатор_коммита, 'сырой результат имеет чужой OID')
    структура = структура_коммита(данные)
    заголовок, сообщение = данные.split(b'\n\n',1)
    строки = заголовок.decode().splitlines()
    def личность(префикс):
        найденные = [э[len(префикс):] for э in строки if э.startswith(префикс)]
        требовать(len(найденные) == 1, 'неоднозначная личность сырого результата')
        return найденные[0]
    return {'коммит':идентификатор_коммита, 'дерево':структура['дерево'],
        'родители':структура['родители'], 'автор':личность('author '),
        'коммиттер':личность('committer '), 'сообщение_sha256':хэш(сообщение)}



def прочитать_исторический_файл(указатель):
    """Отдельный исторический RO-адаптер; общий контракт 0400 сохраняется."""
    поля(указатель, {'путь','sha256'})
    сумма(указатель['sha256'],64)
    try:
        путь = физический(указатель['путь']); до = путь.lstat()
        требовать(stat.S_ISREG(до.st_mode) and до.st_uid == os.getuid() and до.st_nlink == 1
            and stat.S_IMODE(до.st_mode) == 0o600 and 0 < до.st_size <= ПРЕДЕЛ_ИСТОЧНИКА,
            'исторический комплект требует собственного обычного файла mode0600')
        дескриптор = os.open(путь,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
        try:
            требовать(отпечаток(os.fstat(дескриптор)) == отпечаток(до), 'исторический inode подменён до чтения')
            данные = bytearray(); начало_нс = time.perf_counter_ns()
            while len(данные) < до.st_size:
                требовать(time.perf_counter_ns()-начало_нс < 120*1000000000, 'превышен бюджет исторического чтения')
                блок = os.pread(дескриптор,min(1024*1024,до.st_size-len(данные)),len(данные))
                требовать(bool(блок), 'исторический файл усечён')
                данные.extend(блок)
            данные = bytes(данные)
            требовать(отпечаток(os.fstat(дескриптор)) == отпечаток(путь.lstat()) == отпечаток(до)
                and физический(str(путь)) == путь and хэш(данные) == указатель['sha256'],
                'исторический комплект изменён или SHA не совпал')
            return данные
        finally:
            os.close(дескриптор)
    except (OSError,TypeError,UnicodeError) as ошибка:
        raise ValueError('не подтверждён исторический физический комплект') from ошибка


class _РеестрЦепиЯкорей(ЕдиныйНативныйРеестр):
    """Тот же реестр K9 без отбора по текущей адресной паре."""

def _синхронизировать_каталог(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW)
    try: os.fsync(дескриптор)
    finally: os.close(дескриптор)


def _сохранить_долговечный_файл(путь, данные, *, живой=None):
    """O_EXCL, неизменяемые байты, публикация без замены и fsync каталога.

    Временная ссылка остаётся до подтверждения публикации. Незавершённая
    публикация не становится разрешением повторить эффект.
    """
    временный = путь.with_name(путь.name+'.временный')
    дескриптор = os.open(временный, os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW, 0o600)
    try:
        позиция = 0
        while позиция < len(данные):
            записано = os.write(дескриптор, данные[позиция:])
            требовать(записано > 0, 'не завершена долговечная запись')
            позиция += записано
        os.fchmod(дескриптор, 0o400); os.fsync(дескриптор)
        if живой is not None: _пересверить_живой_приём(живой)
        os.link(временный, путь, follow_symlinks=False)
        _синхронизировать_каталог(путь.parent)
        if живой is not None: _пересверить_живой_приём(живой)
        временный.unlink()
        try: _синхронизировать_каталог(путь.parent)
        except OSError:
            os.link(путь, временный, follow_symlinks=False)
            raise
        требовать(прочитать_приватный(путь) == данные, 'долговечная запись не подтвердилась')
    finally:
        os.close(дескриптор)



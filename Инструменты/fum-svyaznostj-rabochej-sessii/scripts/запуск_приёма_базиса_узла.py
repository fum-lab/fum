ПРЕДЕЛ_ИСТОЧНИКА = 32 * 1024 * 1024


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def поля(значение, состав):
    требовать(type(значение) is dict and set(значение) == set(состав),
        'неверные закрытые поля самостоятельного приёма')


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def сумма(значение, длина):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{' + str(длина) + '}', значение),
        'нужен полный канонический идентификатор')
    return значение


def имя(значение):
    требовать(type(значение) is str and значение and not значение.startswith('/')
        and not any(с in значение for с in ('\\', ':', '\x00'))
        and значение == unicodedata.normalize('NFC', значение)
        and not any(unicodedata.category(с).startswith('C') for с in значение)
        and all(э not in ('', '.', '..') and э.casefold() != '.git'
            for э in значение.split('/')), 'небезопасный путь самостоятельного приёма')
    return значение


def идентификатор(значение):
    требовать(type(значение) is str, 'UUID должен быть строкой')
    try:
        требовать(str(uuid.UUID(значение)) == значение, 'неканонический UUID')
    except (AttributeError, ValueError) as ошибка:
        raise ValueError('неканонический UUID') from ошибка
    return значение


def выбор(значение):
    поля(значение, {'коммит', 'путь', 'sha256'})
    сумма(значение['коммит'], 40); имя(значение['путь']); сумма(значение['sha256'], 64)
    требовать(not any(э.startswith('.') for э in значение['путь'].split('/')),
        'скрытый источник самостоятельного приёма')
    return значение


def метаданные(значение):
    поля(значение, {'путь', 'режим', 'тип', 'blob', 'sha256', 'байты'})
    имя(значение['путь']); сумма(значение['blob'], 40); сумма(значение['sha256'], 64)
    требовать(значение['режим'] == '100644' and значение['тип'] == 'blob'
        and type(значение['байты']) is int and 0 < значение['байты'] <= ПРЕДЕЛ_ИСТОЧНИКА,
        'неверный режим, тип или размер выбранного файла')
    return значение


def проверить_контур(описание):
    поля(описание, {'схема', 'K', 'вход', 'файлы'})
    требовать(описание['схема'] == СХЕМА_КОНТУРА and описание['вход'] == ВХОД,
        'неверный выбранный вход контура')
    требовать(type(описание['файлы']) is list and len(описание['файлы']) == 2,
        'контур требует ровно два файла')
    сумма(описание['K'], 40)
    for запись in описание['файлы']:
        метаданные(запись)
    требовать([э['путь'] for э in описание['файлы']] == [ВХОД, СЫРОЙ_МОДУЛЬ],
        'контур требует два фиксированных пути в точном порядке')
    return описание


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True,
        separators=(',', ':'), allow_nan=False) + '\n').encode()


def разобрать(данные):
    требовать(type(данные) is bytes and 0 < len(данные) <= ПРЕДЕЛ_ИСТОЧНИКА,
        'превышен бюджет читающего источника')
    def пары(элементы):
        результат = {}
        for ключ, значение in элементы:
            требовать(ключ not in результат, 'повторный JSON-ключ источника')
            результат[ключ] = значение
        return результат
    def константа(значение):
        raise ValueError('нечисловая JSON-константа источника')
    return json.loads(данные.decode('utf-8'), object_pairs_hook=пары, parse_constant=константа)


def версия(значение):
    if значение is None:
        return
    поля(значение, {'режим', 'тип', 'blob', 'sha256', 'байты'})
    сумма(значение['blob'], 40); сумма(значение['sha256'], 64)
    требовать(значение['режим'] in ('100644', '100755') and значение['тип'] == 'blob'
        and type(значение['байты']) is int and 0 <= значение['байты'] <= ПРЕДЕЛ_ИСТОЧНИКА,
        'неверная версия переносимого файла')


def перечень_версий(значение, ключи):
    требовать(type(значение) is list, 'перечень версий должен быть массивом')
    имена = []
    for запись in значение:
        поля(запись, {'путь'} | set(ключи)); имена.append(имя(запись['путь']))
        for ключ in ключи: версия(запись[ключ])
    требовать(имена == sorted(set(имена), key=lambda э: э.encode()), 'неполный порядок версий')


def проверить_приёмку(описание):
    поля(описание, {'схема', 'узел', 'репозиторий', 'координатор', 'владелец',
        'хэш_корня', 'ветка', 'приёмка_состава', 'семантика', 'первый_цикл', 'контур'})
    требовать(описание['схема'] == СХЕМА_ПРИЁМКИ and описание['узел'] == 'fum-lab/fum'
        and описание['репозиторий'] == 'fum-lab/fum'
        and описание['ветка'] == 'refs/heads/fum-lab/fum', 'чужая ветка состояния')
    for ключ in ('координатор', 'владелец'): идентификатор(описание[ключ])
    требовать(описание['координатор'] != описание['владелец'], 'ROOT не является владельцем')
    сумма(описание['хэш_корня'], 64); выбор(описание['контур'])
    приёмка = описание['приёмка_состава']; поля(приёмка, {'состав', 'решения'})
    состав = приёмка['состав']; поля(состав, {'схема', 'R', 'B', 'K', 'дерево',
        'родители', 'общий_предок', 'входящий_состав', 'пересечения', 'сохранённые'})
    требовать(состав['схема'] == 'fum.состав-базиса-узла.1', 'неверная схема состава')
    for ключ in ('R', 'B', 'K', 'дерево', 'общий_предок'): сумма(состав[ключ], 40)
    требовать(len({состав['R'], состав['B'], состав['K']}) == 3
        and состав['родители'] == [состав['K'], состав['R']], 'разные R/B/K и родители обязательны')
    for ключ in ('входящий_состав', 'пересечения', 'сохранённые'):
        требовать(type(состав[ключ]) is list, 'состав должен быть массивом')
    входящие = состав['входящий_состав']; пути = []
    for запись in входящие:
        поля(запись, {'путь', 'статус', 'R', 'B'}); пути.append(имя(запись['путь']))
        требовать(запись['статус'] in ('A', 'D', 'M'), 'неверный статус состава')
        версия(запись['R']); версия(запись['B'])
        требовать((запись['R'] is None and запись['B'] is not None and запись['статус'] == 'A')
            or (запись['R'] is not None and запись['B'] is None and запись['статус'] == 'D')
            or (запись['R'] is not None and запись['B'] is not None
                and запись['R'] != запись['B'] and запись['статус'] == 'M'), 'статус не совпал с версиями')
    требовать(пути == sorted(set(пути), key=lambda э: э.encode()), 'неполный порядок состава')
    перечень_версий(состав['пересечения'], ('X', 'R', 'K', 'B'))
    перечень_версий(состав['сохранённые'], ('R', 'B'))
    требовать(type(приёмка['решения']) is list, 'решения должны быть массивом')
    решения = []
    for запись in приёмка['решения']:
        поля(запись, {'путь', 'описание'}); решения.append(имя(запись['путь']))
        требовать(type(запись['описание']) is str and запись['описание'].strip(),
            'пересечение требует конкретного решения ROOT')
    требовать(решения == [э['путь'] for э in состав['пересечения']], 'неполный перечень решений')
    семантика = описание['семантика']
    поля(семантика, {'схема', 'B', 'дерево', 'документы', 'сессии'})
    требовать(семантика['схема'] == 'fum.семантика-базиса-узла.1'
        and семантика['B'] == состав['B'] and семантика['дерево'] == состав['дерево']
        and type(семантика['документы']) is list and type(семантика['сессии']) is list,
        'семантика не связана с тем же B/tree')
    документы = []
    for запись in семантика['документы']:
        поля(запись, {'путь', 'дата', 'сырой_sha256', 'содержательный_sha256'})
        документы.append(имя(запись['путь']))
        сумма(запись['сырой_sha256'], 64); сумма(запись['содержательный_sha256'], 64)
        требовать(type(запись['дата']) is str and запись['дата'], 'нет даты семантической записи')
    требовать(документы == sorted(set(документы), key=lambda э: э.encode()), 'неполный порядок документов')
    сессии = семантика['сессии']
    for сессия in сессии: имя(сессия)
    требовать(сессии == sorted(set(сессии)), 'неполный порядок сессий')
    первый = описание['первый_цикл']
    поля(первый, {'акт', 'полномочия', 'идентичность', 'защищённые'})
    выбор(первый['акт']); выбор(первый['полномочия'])
    идентичность = первый['идентичность']
    поля(идентичность, {'узел', 'репозиторий', 'координатор', 'владелец', 'поколение_полномочий'})
    требовать(all(идентичность[к] == описание[к] for к in ('узел', 'репозиторий', 'координатор', 'владелец')),
        'чужая идентичность первого цикла')
    поколение(идентичность['поколение_полномочий'])
    защита = первый['защищённые']
    требовать(type(защита) is list and len(защита) == 6, 'нужны все шесть замороженных файлов')
    for запись in защита: метаданные(запись)
    требовать(len({э['путь'] for э in защита}) == 6, 'повторный защищённый файл')
    return описание


def поколение(значение):
    требовать(type(значение) is str and значение.strip() == значение and значение
        and len(значение.encode()) <= 256
        and not any(unicodedata.category(с).startswith('C') for с in значение),
        'неверное поколение приёма')
    return значение


def сверить_акт(акт, приёмка, выбранная_приёмка):
    """Структура ACT не заменяет нативный допуск на границе эффекта."""
    проверить_приёмку(приёмка); выбор(выбранная_приёмка)
    поля(акт, {'схема', 'координатор', 'исполнитель', 'приёмка', 'область',
        'поколение_приёма', 'контроль'})
    требовать(акт['схема'] == СХЕМА_АКТА
        and акт['координатор'] == приёмка['координатор']
        and акт['исполнитель'] == приёмка['владелец']
        and акт['приёмка'] == выбранная_приёмка, 'ACT не выбрал ту же независимую приёмку')
    требовать(акт['область'] == [э['путь'] for э in приёмка['приёмка_состава']['состав']['входящий_состав']],
        'ACT не разрешил весь точный состав R→B')
    поколение(акт['поколение_приёма'])
    поля(акт['контроль'], {'ветка', 'коммит'}); сумма(акт['контроль']['коммит'], 40)
    требовать(акт['контроль']['коммит'] == выбранная_приёмка['коммит'],
        'control должен закреплять выбранное поколение независимой приёмки')
    ветка = акт['контроль']['ветка']
    требовать(type(ветка) is str and ветка.startswith('refs/heads/codex/')
        and имя(ветка) == ветка and not any(с in ветка for с in ' \x7e^?*[')
        and '..' not in ветка and '@{' not in ветка and not ветка.endswith('.')
        and all(not э.startswith('.') and not э.endswith('.lock') for э in ветка.split('/')),
        'нужен отдельный точный control ref')
    return акт


def сверить_результаты(приёмка, состав, семантика, защищённые):
    проверить_приёмку(приёмка)
    требовать(байты(приёмка['приёмка_состава']['состав']) == байты(состав)
        and байты(приёмка['семантика']) == байты(семантика)
        and байты(приёмка['первый_цикл']['защищённые']) == байты(защищённые),
        'независимая приёмка не совпала с полными сырыми расчётами')


def команда_гит(корень, аргументы):
    исполняемый = shutil.which('git')
    требовать(исполняемый is not None and Path(исполняемый).is_absolute(), 'нет выбранного Git')
    среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_SYSTEM=os.devnull,
        GIT_CONFIG_GLOBAL=os.devnull, GIT_NO_LAZY_FETCH='1', GIT_TERMINAL_PROMPT='0')
    команда = [исполняемый, '--no-replace-objects', '--no-optional-locks',
        '-c', 'core.hooksPath=' + os.devnull, '-c', 'core.fsmonitor=false',
        '-c', 'core.pager=cat', '-C', str(корень), *аргументы]
    return команда, среда


def гит(корень, *аргументы, допустимые_коды=(0,)):
    команда, среда = команда_гит(корень, аргументы)
    ответ = subprocess.run(команда, env=среда, capture_output=True, timeout=60)
    требовать(ответ.returncode in допустимые_коды, 'не удалось прочитать выбранный Git-источник')
    return ответ.returncode, ответ.stdout


def объект(корень, идентификатор_объекта, тип, *, читатель=None):
    if читатель is not None:
        return читатель.прочитать(идентификатор_объекта, тип)
    сумма(идентификатор_объекта, 40)
    требовать(гит(корень, 'cat-file', '-t', идентификатор_объекта)[1].strip() == тип.encode(),
        'неверный тип выбранного объекта')
    размер = гит(корень, 'cat-file', '-s', идентификатор_объекта)[1].strip()
    требовать(re.fullmatch(b'[0-9]+', размер) and int(размер) <= ПРЕДЕЛ_ИСТОЧНИКА,
        'выбранный объект превышает бюджет до чтения')
    данные = гит(корень, 'cat-file', тип, идентификатор_объекта)[1]
    требовать(len(данные) == int(размер) and hashlib.sha1(тип.encode() + b' '
        + str(len(данные)).encode() + b'\0' + данные).hexdigest() == идентификатор_объекта,
        'выбранный объект не совпал с сырыми байтами')
    return данные


def структура_коммита(данные):
    требовать(b'\n\n' in данные, 'неполный начальный заголовок commit')
    строки = данные.split(b'\n\n', 1)[0].split(b'\n')
    требовать(строки[0].startswith(b'tree '), 'нет начального дерева commit')
    дерево = сумма(строки[0][5:].decode('ascii'), 40)
    родители = []; позиция = 1
    while позиция < len(строки) and строки[позиция].startswith(b'parent '):
        родители.append(сумма(строки[позиция][7:].decode('ascii'), 40)); позиция += 1
    требовать(not any(э.startswith((b'tree ', b'parent ')) for э in строки[позиция:])
        and len(родители) == len(set(родители)) and len(родители) <= 256
        and '0'*40 not in [дерево, *родители], 'неоднозначные начальные tree/parent')
    return {'дерево': дерево, 'родители': родители}


def структура_дерева(данные, *, проверка_срока=None):
    итог = {}; свёрнутые = set(); позиция = 0; прежний = None
    while позиция < len(данные):
        if проверка_срока is not None:
            проверка_срока()
        требовать(len(итог) < 200000, 'превышен состав начального дерева')
        пробел = данные.find(b' ', позиция); нуль = данные.find(b'\0', пробел + 1)
        требовать(пробел > позиция and нуль > пробел and нуль + 21 <= len(данные),
            'усечённое начальное Git-дерево')
        режим = данные[позиция:пробел]
        требовать(режим in (b'40000', b'100644', b'100755', b'120000', b'160000'),
            'неверный режим начального Git-дерева')
        сырое_имя = данные[пробел + 1:нуль]; часть = имя(сырое_имя.decode('utf-8'))
        требовать('/' not in часть and часть not in итог and часть.casefold() not in свёрнутые,
            'повторное либо неоднозначное имя начального дерева')
        свёрнутые.add(часть.casefold())
        ключ = сырое_имя + (b'/' if режим == b'40000' else b'')
        требовать(прежний is None or прежний < ключ, 'нарушен начальный порядок Git-дерева')
        прежний = ключ; дочерний = данные[нуль + 1:нуль + 21].hex()
        требовать(дочерний != '0'*40, 'нулевой объект начального дерева')
        тип = 'tree' if режим == b'40000' else 'commit' if режим == b'160000' else 'blob'
        итог[часть] = (режим.decode(), тип, дочерний); позиция = нуль + 21
    return итог


def точный_файл(корень, коммит, путь, *, читатель=None):
    if читатель is None:
        with НачальныеОбъекты(корень) as собственный:
            return точный_файл(корень, коммит, путь, читатель=собственный)
    части = имя(путь).split('/')
    требовать(len(части) <= 128, 'превышена глубина начального пути')
    дерево = структура_коммита(объект(корень, коммит, 'commit', читатель=читатель))['дерево']
    for номер, часть in enumerate(части):
        запись = структура_дерева(объект(корень, дерево, 'tree', читатель=читатель),
            проверка_срока=читатель.проверить_срок).get(часть)
        if запись is None:
            return None
        if номер == len(части) - 1:
            return запись
        if запись[:2] != ('40000', 'tree'):
            return None
        дерево = запись[2]


class НачальныеОбъекты:
    """Доверенный bootstrap читает полную историю без интерпретации grafts/shallow."""
    def __init__(сам, корень):
        сам.команда, сам.среда = команда_гит(корень, ('cat-file', '--batch'))
        сам.процесс = None; сам.конец = time.monotonic() + 120
        сам.количество = 0; сам.объём = 0

    def __enter__(сам):
        сам.процесс = subprocess.Popen(сам.команда, env=сам.среда,
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, bufsize=0)
        return сам

    def __exit__(сам, *ошибки):
        сам.процесс.stdin.close(); сам.процесс.stdout.close()
        if сам.процесс.poll() is None:
            сам.процесс.terminate()
        try:
            сам.процесс.wait(timeout=5)
        except subprocess.TimeoutExpired:
            сам.процесс.kill(); сам.процесс.wait(timeout=5)

    def проверить_срок(сам):
        требовать(time.monotonic() < сам.конец, 'истёк бюджет начального чтения')

    def отрезок(сам, размер):
        результат = bytearray()
        while len(результат) < размер:
            остаток = сам.конец - time.monotonic()
            требовать(остаток > 0 and select.select([сам.процесс.stdout], [], [], max(0, остаток))[0],
                'истёк бюджет начального чтения')
            кусок = os.read(сам.процесс.stdout.fileno(), min(65536, размер - len(результат)))
            требовать(bool(кусок), 'оборвано начальное чтение объекта')
            результат.extend(кусок)
        return bytes(результат)

    def прочитать(сам, идентификатор_объекта, тип='commit'):
        сумма(идентификатор_объекта, 40)
        требовать(тип in ('commit', 'tree', 'blob'), 'неверный запрошенный начальный тип')
        требовать(сам.количество < 200000 and time.monotonic() < сам.конец,
            'превышен бюджет начальной истории')
        запрос = (идентификатор_объекта + '\n').encode()
        требовать(os.write(сам.процесс.stdin.fileno(), запрос) == len(запрос), 'оборван запрос начального объекта')
        заголовок = bytearray()
        while not заголовок.endswith(b'\n'):
            требовать(len(заголовок) < 256, 'превышен начальный заголовок объекта')
            заголовок.extend(сам.отрезок(1))
        совпадение = re.fullmatch(rb'([0-9a-f]{40}) (commit|tree|blob) (0|[1-9][0-9]*)\n', заголовок)
        требовать(совпадение is not None and совпадение[1].decode() == идентификатор_объекта
            and совпадение[2].decode() == тип, 'нет точного сырого объекта начальной истории')
        размер = int(совпадение[3]); сам.количество += 1; сам.объём += размер
        требовать(размер <= ПРЕДЕЛ_ИСТОЧНИКА and сам.объём <= 2*1024*1024*1024,
            'превышен размер начальных объектов до чтения')
        данные = сам.отрезок(размер)
        требовать(сам.отрезок(1) == b'\n' and hashlib.sha1(тип.encode() + b' '
            + str(размер).encode() + b'\0' + данные).hexdigest() == идентификатор_объекта,
            'начальный объект не совпал с сырыми байтами')
        сам.проверить_срок()
        return данные


def проверить_начальную_историю(корень, состояние, источники, *, читатель=None):
    if читатель is None:
        with НачальныеОбъекты(корень) as собственный:
            return проверить_начальную_историю(корень, состояние, источники, читатель=собственный)
    граф = {}; назначенные = {состояние['B'], *(э['коммит'] for э in источники)}
    очередь = list(назначенные)
    while очередь:
        читатель.проверить_срок(); текущий = очередь.pop()
        граф[текущий] = структура_коммита(читатель.прочитать(текущий))
        for родитель in граф[текущий]['родители']:
            читатель.проверить_срок()
            if родитель not in назначенные:
                требовать(len(назначенные) < 200000, 'превышен состав начальной истории')
                назначенные.add(родитель); очередь.append(родитель)
    требовать(граф[состояние['B']]['родители'] == [состояние['K'], состояние['R']],
        'начальные родители B не совпали с K и R')
    требовать(граф[состояние['B']]['дерево'] == состояние['дерево'],
        'начальное дерево B не совпало с независимой приёмкой')
    def предки(начало):
        результат = {начало}; очередь = [начало]
        while очередь:
            читатель.проверить_срок(); текущий = очередь.pop()
            for родитель in граф[текущий]['родители']:
                читатель.проверить_срок()
                if родитель not in результат:
                    результат.add(родитель); очередь.append(родитель)
        return результат
    внутри = предки(состояние['B'])
    требовать(all(э['коммит'] not in внутри for э in источники),
        'B не вправе поставлять собственную приёмку или ACT')
    for ранний, поздний in zip(источники, источники[1:]):
        требовать(ранний['коммит'] != поздний['коммит']
            and ранний['коммит'] in предки(поздний['коммит']),
            'независимые приёмки не связаны историей ROOT')


def прочитать_источник(корень, выбранный, *, читатель=None):
    if читатель is None:
        with НачальныеОбъекты(корень) as собственный:
            return прочитать_источник(корень, выбранный, читатель=собственный)
    выбор(выбранный)
    запись = точный_файл(корень, выбранный['коммит'], выбранный['путь'], читатель=читатель)
    требовать(запись is not None and запись[:2] == ('100644', 'blob'),
        'источник должен быть обычным точным blob')
    данные = объект(корень, запись[2], 'blob', читатель=читатель)
    требовать(хэш(данные) == выбранный['sha256'], 'подменён сырой SHA источника')
    return данные


def физический(значение, *, каталог=False):
    требовать(type(значение) is str and Path(значение).is_absolute(), 'нужен абсолютный физический путь')
    путь = Path(значение)
    требовать(str(путь) == значение and путь == путь.resolve(strict=True), 'алиас физического пути запрещён')
    предок = Path(путь.anchor)
    for часть in путь.parts[1:]:
        требовать(часть in os.listdir(предок), 'нет точного регистра физического пути')
        предок /= часть
        состояние = предок.lstat()
        требовать(not stat.S_ISLNK(состояние.st_mode), 'symlink физического источника запрещён')
    требовать((stat.S_ISDIR if каталог else stat.S_ISREG)(состояние.st_mode), 'неверный тип физического источника')
    return путь


def отпечаток(состояние):
    return tuple(getattr(состояние, к) for к in ('st_dev', 'st_ino', 'st_mode',
        'st_uid', 'st_gid', 'st_nlink', 'st_size', 'st_mtime_ns', 'st_ctime_ns'))


def прочитать_приватный(путь):
    путь = физический(str(путь))
    до = путь.lstat()
    требовать(до.st_uid == os.getuid() and до.st_nlink == 1
        and stat.S_IMODE(до.st_mode) == 0o400, 'приватная копия должна быть собственной, неизменяемой и mode0400')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        с = os.fstat(дескриптор)
        требовать(отпечаток(с) == отпечаток(до), 'физический источник заменён перед чтением')
        with os.fdopen(дескриптор, 'rb', closefd=False) as поток:
            данные = поток.read(ПРЕДЕЛ_ИСТОЧНИКА + 1)
        требовать(0 < len(данные) <= ПРЕДЕЛ_ИСТОЧНИКА
            and отпечаток(os.fstat(дескриптор)) == отпечаток(до)
            and отпечаток(путь.lstat()) == отпечаток(до), 'физический источник изменился во время чтения')
    finally:
        os.close(дескриптор)
    return данные


def проверить_импорты(данные):
    разрешены = {'ast', 'hashlib', 'json', 'os', 'datetime', 'pathlib', 'posixpath',
        're', 'select', 'shutil', 'stat', 'subprocess', 'time', 'types', 'unicodedata',
        'uuid', 'argparse', 'sys', 'base64', 'fcntl'}
    for узел in ast.walk(ast.parse(данные.decode('utf-8'))):
        if isinstance(узел, ast.Import):
            требовать(all(э.name in разрешены for э in узел.names), 'контур имеет внешнюю Python-зависимость')
        elif isinstance(узел, ast.ImportFrom):
            требовать(узел.level == 0 and узел.module in разрешены, 'контур имеет проектный или относительный импорт')
        elif isinstance(узел, ast.Call) and isinstance(узел.func, ast.Name):
            требовать(узел.func.id != '__import__', 'динамический импорт контура запрещён')


def загрузить_контур(корень, каталог, описание, *, читатель=None):
    """Только чтение; ROOT должен заранее независимо принять BOOT и выбрать описание."""
    if читатель is None:
        with НачальныеОбъекты(корень) as собственный:
            return загрузить_контур(корень, каталог, описание, читатель=собственный)
    проверить_контур(описание)
    корень = физический(str(корень), каталог=True); каталог = физический(str(каталог), каталог=True)
    требовать(корень != каталог and корень not in каталог.parents and каталог not in корень.parents,
        'Q и W должны быть внешними друг другу')
    состояние = каталог.lstat()
    требовать(состояние.st_uid == os.getuid() and stat.S_IMODE(состояние.st_mode) == 0o700,
        'Q должен быть собственным mode0700')
    исходники = {}
    for запись in описание['файлы']:
        требовать(точный_файл(корень, описание['K'], запись['путь'], читатель=читатель)
            == ('100644', 'blob', запись['blob']), 'файл контура не принадлежит точному K')
        данные = объект(корень, запись['blob'], 'blob', читатель=читатель)
        требовать(len(данные) == запись['байты'] and хэш(данные) == запись['sha256'],
            'подменён исполняемый blob контура')
        требовать(прочитать_приватный(каталог / запись['путь']) == данные,
            'физические исполняемые байты Q не совпали с K')
        проверить_импорты(данные); исходники[запись['путь']] = данные
    читатель.проверить_срок()
    модуль = types.ModuleType('_fum_закреплённый_базис')
    модуль.__file__ = описание['K'] + ':' + СЫРОЙ_МОДУЛЬ
    код = compile(исходники[СЫРОЙ_МОДУЛЬ], модуль.__file__, 'exec')
    читатель.проверить_срок()
    exec(код, модуль.__dict__)
    with модуль.ПакетСырыхОбъектов(корень) as читатель:
        граф = модуль.замкнуть_историю(читатель, (описание['K'],))
        таблица = модуль.сырая_таблица(читатель, граф[описание['K']]['дерево'])
        модуль.коллизии([таблица])
        for запись in описание['файлы']:
            требовать(таблица.get(запись['путь']) == ('100644', 'blob', запись['blob']),
                'файл контура не принадлежит точному K')
    return модуль


def проверить(корень, каталог, выбранный_контур, выбранная_приёмка, выбранный_акт):
    """Полная читающая сверка; возвращаемый результат не разрешает отложенный FF."""
    корень = физический(str(корень), каталог=True)
    with НачальныеОбъекты(корень) as начальный:
        описание = разобрать(прочитать_источник(корень, выбранный_контур, читатель=начальный))
        проверить_контур(описание)
        приёмка = разобрать(прочитать_источник(корень, выбранная_приёмка, читатель=начальный))
        проверить_приёмку(приёмка)
        требовать(приёмка['контур'] == выбранный_контур
            and приёмка['приёмка_состава']['состав']['K'] == описание['K']
            and приёмка['хэш_корня'] == хэш(str(корень).encode()), 'приёмка выбрала другой K или W')
        акт = разобрать(прочитать_источник(корень, выбранный_акт, читатель=начальный))
        сверить_акт(акт, приёмка, выбранная_приёмка)
        состояние = приёмка['приёмка_состава']['состав']
        источники = (выбранный_контур, выбранная_приёмка, выбранный_акт)
        проверить_начальную_историю(корень, состояние, источники, читатель=начальный)
        модуль = загрузить_контур(корень, каталог, описание, читатель=начальный)
    модуль.корень_гит(корень)
    with модуль.ПакетСырыхОбъектов(корень) as читатель:
        источники = (выбранный_контур, выбранная_приёмка, выбранный_акт)
        граф = модуль.замкнуть_историю(читатель, tuple(э['коммит'] for э in источники))
        for выбранный in источники:
            таблица = модуль.сырая_таблица(читатель, граф[выбранный['коммит']]['дерево'])
            модуль.коллизии([таблица])
            запись = таблица.get(выбранный['путь'])
            требовать(запись is not None and запись[:2] == ('100644', 'blob'),
                'сырой источник приёмки отсутствует или имеет неверный тип')
            данные = читатель.прочитать(запись[2], 'blob', сохранить=True)
            требовать(хэш(данные) == выбранный['sha256'], 'сырая история приёмки изменилась')
    состав = модуль.состав_базиса(корень, состояние['R'], состояние['B'], состояние['K'])
    модуль.сверить_состав(состав, приёмка['приёмка_состава'])
    первый = приёмка['первый_цикл']
    защищённые = модуль.сверить_первый_цикл(корень, состояние['R'], состояние['B'],
        первый['акт'], первый['полномочия'], первый['идентичность'], первый['защищённые'])
    первые_полномочия = разобрать(прочитать_источник(корень, первый['полномочия']))
    требовать(первые_полномочия['хэш_корня'] == приёмка['хэш_корня']
        and первые_полномочия['ветка'] == приёмка['ветка'], 'первый цикл принадлежит другому W/ref')
    семантика = модуль.семантика_базиса(корень, состояние['B'])
    сверить_результаты(приёмка, состав, семантика, защищённые)
    return {'схема': 'fum.сверка-приёма-базиса-узла.1', 'состав': состав,
        'семантика': семантика, 'защищённые': защищённые,
        'приёмка': выбранная_приёмка, 'акт': выбранный_акт, 'контур': выбранный_контур}



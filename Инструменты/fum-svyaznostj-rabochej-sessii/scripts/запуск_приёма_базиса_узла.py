def _классифицировать_нативную_запись(запись,данные,источник,координатор,владелец,описание=None):
    if описание is None:
        описание=_первичная_управляющая_запись(запись,данные,источник,координатор,владелец)
    if описание['класс']!='неразобрано': return описание
    д=запись['payload']
    try:
        if (запись['type']=='event_msg' and д.get('type')=='item_started'
                and type(д.get('item')) is dict and д['item'].get('type')=='McpToolCall'):
            # Прочие start-формы остаются unknown до первичного свидетельства.
            _нативная_отправка_запись(запись,источник,фаза='item_started')
            описание['класс']='начало-вызова'
        else:
            описание['класс']=класс_служебного_содержимого(запись,источник)
    except (KeyError,TypeError,AttributeError,UnicodeError,RecursionError) as ошибка:
        raise ValueError('повреждённое закрытое содержимое нативной рамки') from ошибка
    if 'item' in д: описание['id']=д['item']['id']
    if 'call_id' in д: описание['call_id']=д['call_id']
    return описание


class УчётНативныхКопий:
    """Чистый учёт представлений; смысл оригиналов и LIVE полнота проверяются отдельно."""
    def __init__(сам, источник, координатор, владелец):
        for э in (источник,координатор,владелец): идентификатор(э)
        требовать(координатор!=владелец and источник in (координатор,владелец), 'чужой источник копий')
        сам.источник=источник; сам.координатор=координатор; сам.владелец=владелец
        сам.ordinal=-1; сам.id=set(); сам.оригинал=None; сам.скопирован=False
        сам.обязательная=False; сам.оригиналы=[]; сам.копии=[]
        сам.ошибка=False; сам.закрыт=False; сам.сжатый=False
        сам.число_оригиналов=0; сам.число_копий=0

    def наблюдать(сам, данные):
        требовать(not сам.ошибка and not сам.закрыт, 'учёт уже закрыт либо содержит ошибку')
        try:
            результат=сам._наблюдать(данные)
            if результат['класс']=='неразобрано': сам.ошибка=True
            return разобрать(байты(результат))
        except (ValueError,UnicodeError,RecursionError):
            сам.ошибка=True
            raise

    def _наблюдать(сам, данные):
        return сам._наблюдать_запись(данные,нативная_строка(данные))

    def _наблюдать_запись(сам,данные,запись):
        д=запись['payload']; тип=запись['type']
        требовать(запись['ordinal']>сам.ordinal, 'обратный порядок первичных копий')
        сам.ordinal=запись['ordinal']
        ключ=None
        if тип=='response_item' and 'id' in д: ключ=('response',д['id'])
        elif тип=='event_msg' and д.get('type') in ('item_completed','item_started'):
            э=рамка_элемента(запись,сам.источник); ключ=('event',э['id'],д['type'])
        if ключ is not None:
            требовать(type(ключ[1]) is str and ключ[1] and ключ not in сам.id,
                'повторный первичный ID до отбора адреса')
            сам.id.add(ключ)
        копия=тип=='event_msg' and д.get('type')=='item_completed' and д['item']['type'] in (
            'UserMessage','FunctionCallOutput')
        if копия:
            э=рамка_элемента(запись,сам.источник)
            требовать(сам.оригинал is not None and not сам.скопирован, 'копия без отдельного оригинала либо повтор')
            о,описание=сам.оригинал; п=о['payload']
            ход=п['internal_chat_message_metadata_passthrough']['turn_id']
            требовать(д['turn_id']==ход, 'копия относится к другому ходу')
            if э['type']=='UserMessage':
                поля(э, {'type','id','client_id','content'})
                требовать(п['type']=='message' and п['role']=='user'
                    and type(э['client_id']) is str and type(э['content']) is list and э['content'],
                    'неизвестная версия пользовательской копии')
                части=[]
                for ч in э['content']:
                    поля(ч, {'type','text','text_elements'})
                    требовать(ч['type']=='text' and type(ч['text']) is str and ч['text_elements']==[],
                        'неизвестная часть пользовательской копии')
                    части.append({'type':'input_text','text':ч['text']})
                требовать(байты(части)==байты(п['content']), 'текст первичного ввода и копии расходится')
            else:
                поля(э, {'type','id','name','namespace','output'})
                требовать(п['type']=='function_call_output' and 'call_id' not in п
                    and all(type(э[к]) is str and э[к]==п[к] for к in ('id','name','namespace','output')),
                    'первичный FCO и копия расходятся')
            сам.скопирован=True; сам.обязательная=False
            результат={'id':э['id'],'sha256':хэш(данные),'оригинал_sha256':описание['sha256']}
            сам.число_копий+=1
            if not сам.сжатый: сам.копии.append(результат)
            return dict(результат,класс='точная-копия')
        описание=_первичная_управляющая_запись(запись,данные,сам.источник,сам.координатор,сам.владелец)
        if описание['класс']=='неразобрано':
            try:
                return _классифицировать_нативную_запись(запись,данные,сам.источник,сам.координатор,сам.владелец,описание)
            except ValueError:
                # Исторический API копий сохраняет sticky unknown и не доказывает RPC-причинность.
                return описание
        if (тип=='response_item' and (описание['класс']=='первичный-ввод'
                or д.get('type')=='function_call_output' and 'call_id' not in д)):
            требовать(not сам.обязательная, 'предыдущий пользовательский оригинал остался без копии')
            сам.обязательная=False
            if описание['класс']=='первичный-ввод' and 'metadata' in запись:
                мета=запись['metadata']
                обязательные={'client_authored','user_input_order','retained_source'}
                требовать(обязательные<=set(мета)<=обязательные|{'mcp_attribution'},
                    'неизвестная оболочка пользовательского оригинала')
                retained=мета['retained_source']['id']
                требовать(retained['role']=='user' and retained['message_id']==д['id']
                    and retained['turn_id']==д['internal_chat_message_metadata_passthrough']['turn_id'],
                    'аннотация пользовательского оригинала расходится')
                сам.обязательная=True
            оригинал=запись
            if сам.сжатый:
                нужные=('type','role','content','id','name','namespace','output')
                сохранённое_содержимое={к:д[к] for к in нужные if к in д}
                сохранённое_содержимое['internal_chat_message_metadata_passthrough']={
                    'turn_id':д['internal_chat_message_metadata_passthrough']['turn_id']}
                оригинал={'payload':сохранённое_содержимое}
            сам.оригинал=(оригинал,описание); сам.скопирован=False
        сам.число_оригиналов+=1
        if not сам.сжатый: сам.оригиналы.append(описание)
        return описание

    def завершить(сам):
        требовать(not сам.ошибка and not сам.закрыт, 'учёт уже закрыт либо содержит ошибку')
        if сам.обязательная:
            сам.ошибка=True
            raise ValueError('пользовательский оригинал остался без точной event-копии')
        сам.закрыт=True
        if сам.сжатый:
            return {'схема':'fum.сжатый-учёт-копий.2','источник':сам.источник,
                'оригиналов':сам.число_оригиналов,'точных_копий':сам.число_копий,
                'виденных_ID':len(сам.id),'полнота_копий_доказана':True,
                'полнота_истории_доказана':False,'разрешение_эффекта':False}
        return разобрать(байты({'схема':'fum.сверка-копий-первичных-рамок.1','источник':сам.источник,
            'оригиналы':сам.оригиналы,'копии':сам.копии,'полнота_копий_доказана':True,
            'полнота_истории_доказана':False,'разрешение_эффекта':False}))


def сверить_копии_первичных_рамок(строки, источник, координатор, владелец):
    # Публичная сверка конечного потока сохраняет отказ на orphan/pending RPC.
    учёт=ЕдиныйНативныйРеестр(источник,координатор,владелец)
    for данные in строки:
        учёт.наблюдать(данные)
    return учёт.завершить()['копии']


class ЕдиныйНативныйРеестр:
    """Чистый непрерывный учёт одного потока; физический источник и LIVE проверяются отдельно.

    Вызывающая сторона не передаёт исходное состояние или число незавершённых вызовов.
    Состояние префикса переносится только
    тем же экземпляром после наблюдения его RAW; завершать промежуточный префикс нельзя.
    """
    ПРЕДЕЛ_РАМОК=131072
    ПРЕДЕЛ_БАЙТОВ=32*1024*1024*1024

    def __init__(сам, источник, координатор, владелец):
        сам.копии=УчётНативныхКопий(источник,координатор,владелец)
        сам.источник=источник; сам.вызовы={}; сам.учёт_элементов={}; сам.управляющие=[]
        сам.рамок=0; сам.байтов=0; сам.ошибка=False; сам.закрыт=False; сам.сжатый=False
        сам.виденные_обычные_вызовы=set(); сам.виденные_элементы=set()

    def наблюдать(сам,данные):
        требовать(not сам.ошибка and not сам.закрыт, 'единый реестр закрыт либо содержит ошибку')
        try:
            return разобрать(байты(сам._наблюдать_запись(данные,нативная_строка(данные))))
        except (ValueError,KeyError,TypeError,AttributeError,UnicodeError,RecursionError) as ошибка:
            сам.ошибка=True; сам.копии.ошибка=True
            raise ValueError(str(ошибка)) from ошибка

    def _наблюдать_запись(сам,данные,запись,место=None):
        требовать(not сам.ошибка and not сам.закрыт, 'единый реестр закрыт либо содержит ошибку')
        try:
            требовать(type(данные) is bytes and сам.рамок<сам.ПРЕДЕЛ_РАМОК
                and сам.байтов+len(данные)<=сам.ПРЕДЕЛ_БАЙТОВ, 'превышен бюджет единого реестра')
            д=запись['payload']; тип=запись['type']
            описание=(сам.копии._наблюдать_запись(данные,запись) if сам.сжатый
                else сам.копии.наблюдать(данные))
            требовать(описание['класс']!='неразобрано', 'неизвестная рамка до адресного отбора')
            сам.рамок+=1; сам.байтов+=len(данные)
            if тип=='response_item' and д.get('type') in ('function_call','custom_tool_call'):
                связь=д['call_id']
                требовать(связь not in сам.виденные_обычные_вызовы, 'повторный RPC call_id до адресного отбора')
                сам.виденные_обычные_вызовы.add(связь)
                сам.вызовы[связь]={'call_id':связь,'вид':д['type'],
                    'turn_id':д['internal_chat_message_metadata_passthrough']['turn_id'],
                    'вызов_sha256':описание['sha256'],'исход_sha256':None}
            elif тип=='response_item' and д.get('type') in (
                    'function_call_output','custom_tool_call_output') and 'call_id' in д:
                вызов=сам.вызовы.get(д['call_id'])
                требовать(вызов is not None and вызов['исход_sha256'] is None,
                    'RPC output без preceding call либо повторный исход')
                требовать(д['type']==вызов['вид']+'_output'
                    and д['internal_chat_message_metadata_passthrough']['turn_id']==вызов['turn_id'],
                    'RPC исход другого вида либо хода')
                вызов['исход_sha256']=описание['sha256']
                if сам.сжатый: del сам.вызовы[д['call_id']]
            elif (тип=='event_msg' and д.get('type') in ('item_started','item_completed')
                    and д['item']['type']=='McpToolCall'):
                э=д['item']; номер_учтённого_элемента=э['id']
                сигнатура={к:э[к] for к in ('type','id','server','tool','arguments')}
                for к in ('pluginId','readOnlyHint'):
                    if к in э: сигнатура[к]=э[к]
                сигнатура.update({к:д[к] for к in ('thread_id','turn_id','started_at_ms')})
                отпечаток_сигнатуры=хэш(байты(сигнатура)); вызов=сам.учёт_элементов.get(номер_учтённого_элемента)
                if д['type']=='item_started':
                    требовать(номер_учтённого_элемента not in сам.виденные_элементы, 'MCP start после исхода либо повторное начало')
                    сам.виденные_элементы.add(номер_учтённого_элемента)
                    сам.учёт_элементов[номер_учтённого_элемента]={'id':номер_учтённого_элемента,'сигнатура_sha256':отпечаток_сигнатуры,
                        'начало_sha256':описание['sha256'],'исход_sha256':None,
                        'начало_завершено_ms':д['completed_at_ms']}
                else:
                    if вызов is None:
                        требовать(номер_учтённого_элемента not in сам.виденные_элементы, 'повторный MCP исход')
                        сам.виденные_элементы.add(номер_учтённого_элемента)
                        # Поддержанная completed-only MCP-рамка содержит вызов и его исход.
                        # Её item.id никогда не закрывает обычный RPC call_id.
                        вызов={'id':номер_учтённого_элемента,'сигнатура_sha256':отпечаток_сигнатуры,'начало_sha256':None,
                            'исход_sha256':None,'начало_завершено_ms':None}
                        сам.учёт_элементов[номер_учтённого_элемента]=вызов
                    требовать(вызов['исход_sha256'] is None
                        and вызов['сигнатура_sha256']==отпечаток_сигнатуры
                        and (вызов['начало_завершено_ms'] is None
                            or вызов['начало_завершено_ms']<=д['completed_at_ms']),
                        'MCP исход расходится с началом либо повторён')
                    вызов['исход_sha256']=описание['sha256']
                    if сам.сжатый: del сам.учёт_элементов[номер_учтённого_элемента]
            if описание['класс'] in ('первичный-ввод','первичная-отмена',
                    'адресная-отправка','адресное-получение'):
                управление=dict(описание,ordinal=запись['ordinal'])
                if сам.сжатый:
                    управление={к:управление[к] for к in ('класс','id','ordinal','sha256','содержимое_sha256')}
                    управление['место']=место
                сам.управляющие.append(управление)
            return dict(описание,ordinal=запись['ordinal'])
        except (ValueError,KeyError,TypeError,AttributeError,UnicodeError,RecursionError) as ошибка:
            сам.ошибка=True; сам.копии.ошибка=True
            raise ValueError(str(ошибка)) from ошибка

    def завершить(сам):
        требовать(not сам.ошибка and not сам.закрыт, 'единый реестр закрыт либо содержит ошибку')
        try:
            требовать(сам.рамок>0, 'пустой поток не доказывает нативную историю')
            требовать(all(э['исход_sha256'] is not None for э in сам.вызовы.values())
                and all(э['исход_sha256'] is not None for э in сам.учёт_элементов.values()),
                'незавершённый вызов до адресного отбора')
            копии=сам.копии.завершить(); сам.закрыт=True
            if сам.сжатый:
                return {'схема':'fum.сжатый-нативный-реестр.2','источник':сам.источник,
                    'рамок':сам.рамок,'байтов_сырых_данных':сам.байтов,
                    'последний_порядок':сам.копии.ordinal,'копии':копии,
                    'учтённых_обычных_вызовов':len(сам.виденные_обычные_вызовы),'учтённых_элементов':len(сам.виденные_элементы),
                    'управляющие_оригиналы':сам.управляющие,
                    'полнота_истории_доказана':False,'разрешение_эффекта':False}
            return разобрать(байты({'схема':'fum.единый-реестр-нативных-рамок.1',
                'источник':сам.источник,'рамок':сам.рамок,'байтов_сырых_данных':сам.байтов,
                'последний_порядок':сам.копии.ordinal,'копии':копии,
                'управляющие_оригиналы':сам.управляющие,
                'вызовы_инструментов':list(сам.вызовы.values()),'элементы':list(сам.учёт_элементов.values()),
                'полнота_истории_доказана':False,'разрешение_эффекта':False}))
        except (ValueError,UnicodeError,RecursionError):
            сам.ошибка=True
            raise


class _СжатыйНативныйРеестр(ЕдиныйНативныйРеестр):
    """Внутренний сборщик: точные ID остаются, завершённые payload освобождаются."""
    def __init__(сам,источник,координатор,владелец,текст):
        super().__init__(источник,координатор,владелец)
        сам.сжатый=True; сам.копии.сжатый=True
        сам.координатор=координатор; сам.владелец=владелец; сам.текст=текст
        сам.оболочка_приёма=('<codex_delegation>\n  <source_thread_id>'+координатор
            +'</source_thread_id>\n  <input>'+html.escape(текст,quote=False)+'</input>\n</codex_delegation>')
        сам.кандидат=None; сам.число_кандидатов=0; сам.начала_пары={}; сам.начало_пары=None
        сам.профиль={}

    def _учесть_строку(сам,данные,запись,место):
        описание=сам._наблюдать_запись(данные,запись,место)
        д=запись['payload']; класс=описание['класс']
        кандидат=False; начало=None
        if сам.источник==сам.координатор:
            if (класс=='начало-вызова' and д['item']['arguments']['prompt']==сам.текст
                    and д['item']['arguments']['threadId']==сам.владелец):
                # Начало уже полностью проверено. Для прежнего буквального сравнения
                # нужны аргументы/часы/identity; произвольный start.result не сохраняется.
                сохранённый_элемент={к:д['item'][к] for к in ('type','id','server','tool','pluginId','status','duration')}
                сохранённый_элемент['arguments']=dict(д['item']['arguments'],prompt=сам.текст)
                сохранённый_элемент['result']={}
                сохранённое_содержимое={к:д[к] for к in ('type','thread_id','turn_id','started_at_ms','completed_at_ms')}
                сохранённое_содержимое['item']=сохранённый_элемент
                сам.начала_пары[д['item']['id']]=({'type':'event_msg','payload':сохранённое_содержимое},описание,место)
            elif запись['type']=='event_msg' and д.get('type')=='item_completed' and д['item']['type']=='McpToolCall':
                начало=сам.начала_пары.pop(д['item']['id'],None)
                кандидат=класс=='адресная-отправка' and д['item']['arguments']['prompt']==сам.текст
        else:
            кандидат=класс=='адресное-получение' and д['output']==сам.оболочка_приёма
        if кандидат:
            сам.число_кандидатов=min(2,сам.число_кандидатов+1)
            if сам.кандидат is None:
                сам.кандидат=(запись,описание,место); сам.начало_пары=начало
        return описание


def сверить_пару_после_полного_учёта(потоки, координатор, владелец, акт, якорь):
    """Два конечных RAW-потока учитываются целиком до отбора пары; это ещё не LIVE.

    Физическое происхождение, RAW-границы и независимый выбор исторического якоря
    остаются обязанностью будущего gate, который пока закрыто отказывает.
    """
    идентификатор(координатор); идентификатор(владелец)
    требовать(координатор!=владелец, 'ROOT и владелец должны различаться')
    поля(потоки,{координатор,владелец})
    реестры={}; описания={}; выбранные={}
    for источник in (координатор,владелец):
        требовать(type(потоки[источник]) is list, 'нужен конечный перечень RAW-строк')
        выбранные[источник]=tuple(потоки[источник])
        требовать(len(выбранные[источник])<=ЕдиныйНативныйРеестр.ПРЕДЕЛ_РАМОК,
            'превышен бюджет конечного потока')
    for источник in (координатор,владелец):
        реестр=ЕдиныйНативныйРеестр(источник,координатор,владелец)
        описания[источник]=[реестр.наблюдать(э) for э in выбранные[источник]]
        реестры[источник]=реестр.завершить()
    текст=текст_нативного_приёма(координатор,владелец,акт,якорь)
    оболочка=('<codex_delegation>\n  <source_thread_id>'+координатор
        +'</source_thread_id>\n  <input>'+html.escape(текст,quote=False)+'</input>\n</codex_delegation>')
    отправки=[]; получения=[]; начала=[]
    for источник in (координатор,владелец):
        for сырые,описание in zip(выбранные[источник],описания[источник]):
            д=нативная_строка(сырые)['payload']
            if источник==координатор:
                if (описание['класс']=='адресная-отправка'
                        and д['item']['arguments']['prompt']==текст):
                    отправки.append((сырые,описание))
                elif описание['класс']=='начало-вызова': начала.append(сырые)
            elif описание['класс']=='адресное-получение' and д['output']==оболочка:
                получения.append((сырые,описание))
    требовать(len(отправки)==len(получения)==1, 'нет единственной адресной пары после полного учёта')
    отправка,описание_отправки=отправки[0]; получение,описание_получения=получения[0]
    номер_учтённого_элемента=нативная_строка(отправка)['payload']['item']['id']
    начала=[э for э in начала if нативная_строка(э)['payload']['item']['id']==номер_учтённого_элемента]
    требовать(len(начала)<=1, 'повторное начало отобранной отправки')
    граница_отправки=(нативная_строка(начала[0])['ordinal'] if начала
        else описание_отправки['ordinal'])
    for источник,граница in ((координатор,граница_отправки),
            (владелец,описание_получения['ordinal'])):
        требовать(not any(э['ordinal']>граница and not (источник==координатор
                and э['sha256']==описание_отправки['sha256'])
            for э in реестры[источник]['управляющие_оригиналы']),
            'поздний управляющий оригинал требует независимой проверки')
    пара=сверить_нативную_пару(отправка,получение,координатор,владелец,акт,якорь,
        начало=None if not начала else начала[0])
    return {'схема':'fum.пара-после-единого-нативного-учёта.1','реестры':реестры,'пара':пара,
        'полнота_истории_доказана':False,'разрешение_эффекта':False}


def абсолютное_имя(значение):
    требовать(type(значение) is str and Path(значение).is_absolute()
        and str(Path(значение)) == значение
        and значение == unicodedata.normalize('NFC', значение)
        and not any(ч in ('.','..') for ч in Path(значение).parts)
        and not any(unicodedata.category(ч).startswith('C') for ч in значение),
        'неканоническое абсолютное имя источника')
    return значение


def граница_нативного_источника(значение):
    поля(значение, {'граница','sha256'})
    требовать(type(значение['граница']) is int and значение['граница'] > 0,
        'неверная граница нативного источника')
    сумма(значение['sha256'],64)
    return значение


def место_нативной_строки(значение):
    поля(значение, {'начало','конец','sha256'})
    требовать(type(значение['начало']) is int and type(значение['конец']) is int
        and 0 <= значение['начало'] < значение['конец']
        and значение['конец'] - значение['начало'] <= ПРЕДЕЛ_НАТИВНОЙ_СТРОКИ,
        'неверные границы нативной строки')
    сумма(значение['sha256'],64)
    return значение


def проверить_якорь(описание):
    """Только закрытая схема ROOT-review. RAW, полнота и действующий ACT — отдельные gates."""
    поля(описание, {'схема','координатор','владелец','узел','репозиторий','хэш_корня',
        'ветка','начальный_коммит','предыдущий_принятый_якорь','начальная_опора',
        'источники','управляющие_эпизоды','итог'})
    требовать(описание['схема'] == 'fum.приёмка-нативной-истории-узла.1'
        and описание['узел'] == описание['репозиторий'] == 'fum-lab/fum'
        and описание['ветка'] == 'refs/heads/fum-lab/fum', 'неверная идентичность якоря')
    for к in ('координатор','владелец'): идентификатор(описание[к])
    требовать(описание['координатор'] != описание['владелец'], 'ROOT и владелец совпали')
    сумма(описание['хэш_корня'],64); сумма(описание['начальный_коммит'],40)
    предыдущий=описание['предыдущий_принятый_якорь']
    if предыдущий is not None: выбор(предыдущий)
    опора=описание['начальная_опора']
    поля(опора, {'R','акт','полномочия','приёмка_ROOT','квитанция_ROOT',
        'подготовка_владельца','квитанция_владельца','начало_владельца',
        'поручение_владельца','получение_владельца','текст_sha256'})
    сумма(опора['R'],40); сумма(опора['текст_sha256'],64)
    for к in ('акт','полномочия','приёмка_ROOT'): выбор(опора[к])
    for к in ('квитанция_ROOT','подготовка_владельца','квитанция_владельца'):
        поля(опора[к], {'путь','sha256'})
        абсолютное_имя(опора[к]['путь']); сумма(опора[к]['sha256'],64)
    for к in ('начало_владельца','поручение_владельца'): граница_нативного_источника(опора[к])

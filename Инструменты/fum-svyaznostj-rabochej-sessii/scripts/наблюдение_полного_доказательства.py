"""Явная профильная оснастка; исходные проверки и их данные не заменяются.

Контекст предназначен для одного потока в отдельном процессе профиля с уже
загруженными модулями. Временные обёртки восстанавливаются при любом выходе.
Это не постоянно подключённый перехватчик и не часть допуска коммита.
"""
import contextlib
import copy
import functools
from pathlib import Path
import time
from unittest import mock


class Наблюдение:
    def __init__(сам, приёмник=None, *, хранить_события=True):
        сам._приёмник = приёмник
        сам._хранить = хранить_события
        сам._события = []
        сам._ошибки = []
        сам._стек = []
        сам._порядок = 0
        сам._рамки = 0
        сам._затраты = 0
        сам._диагностика = False

    def _сбой(сам, ошибка):
        # Даже диагностика MemoryError/KeyboardInterrupt не подменяет исходный
        # результат. Эта граница относится только к коду наблюдения.
        сам._ошибки.append(type(ошибка).__name__)

    def _добавить(сам, событие):
        прежнее = сам._диагностика
        сам._диагностика = True
        начало = time.monotonic_ns()
        try:
            сам._порядок += 1
            событие = {**событие, 'порядок': сам._порядок}
            if сам._хранить:
                сам._события.append(событие)
            if сам._приёмник is not None:
                сам._приёмник(copy.deepcopy(событие))
        except BaseException as ошибка:
            сам._сбой(ошибка)
        finally:
            сам._затраты += time.monotonic_ns() - начало
            сам._диагностика = прежнее

    def обернуть(сам, роль, действие, данные=None):
        @functools.wraps(действие)
        def выполнить(*аргументы, **поля):
            if сам._диагностика:
                return действие(*аргументы, **поля)
            рамка = None
            try:
                сам._рамки += 1
                рамка = сам._рамки
                родитель = сам._стек[-1] if сам._стек else None
                сам._стек.append(рамка)
                начало = time.monotonic_ns()
                сам._добавить({'событие': 'начало', 'роль': роль,
                    'рамка': рамка, 'родитель': родитель, 'монотонные_нс': начало})
            except BaseException as ошибка:
                сам._сбой(ошибка)
            исход = 'отказ'
            результат = None
            try:
                результат = действие(*аргументы, **поля)
                исход = 'успех'
                return результат
            finally:
                try:
                    конец = time.monotonic_ns()
                    сведения = None
                    if исход == 'успех' and данные is not None:
                        прежнее = сам._диагностика
                        сам._диагностика = True
                        try:
                            сведения = данные(аргументы, поля, результат)
                        finally:
                            сам._диагностика = прежнее
                    if рамка is not None:
                        сам._добавить({'событие': 'конец', 'роль': роль,
                            'рамка': рамка, 'родитель': родитель,
                            'монотонные_нс': конец, 'исход': исход, 'данные': сведения})
                except BaseException as ошибка:
                    сам._сбой(ошибка)
                finally:
                    if рамка is not None and сам._стек and сам._стек[-1] == рамка:
                        сам._стек.pop()
        return выполнить

    def срез(сам):
        return {'схема': 'fum.наблюдение-полного-доказательства.1',
            'полон': not сам._ошибки, 'события': copy.deepcopy(сам._события),
            'ошибки_наблюдения': list(сам._ошибки),
            'рамок': сам._рамки, 'событий': сам._порядок,
            'передача_событий_наносекунды': сам._затраты,
            'граница': 'Вложенные интервалы не складываются. Логические байты не являются физическим I/O. '
                'Полон означает отсутствие потерь диагностики, не покрытие всех системных чтений. '
                'Измерена только передача событий, не вся цена оснастки.'}


def _пакет(аргументы, поля, результат):
    дерево = аргументы[1]
    первые = {}
    for путь, объект in дерево.items():
        первые.setdefault(объект, путь)
    return {'пути': len(дерево), 'уникальные_oid': len(первые),
        'полезные_байты_blob': sum(len(результат[п]) for п in первые.values()),
        'логические_байты_по_путям': sum(len(б) for б in результат.values())}


def _сырые(аргументы, поля, результат):
    return {'сырые_байты': len(результат[0]), 'метод': 'буфер исходного FD-чтения'}


def _байты_path(аргументы, поля, результат):
    return {'сырые_байты': len(результат), 'метод': 'буфер исходного Path.read_bytes'}


def _текст(аргументы, поля, результат):
    return {'сырые_байты': None, 'метод': 'текстовый API; сырые байты не наблюдались'}


@contextlib.contextmanager
def наблюдать(связность, журнал, свежесть, *, наблюдатель=None):
    """Без новых чтений/хэшей: метаданные берутся после исходного вызова.

Path.read_bytes учитывает также прямые повторные чтения смешанного Журнала.
Его интервалы вложены в пакет/проверку; они не являются отдельной внешней ценой.
Отсутствующий optional hook просто не покрывается, перечень подключений явный.
"""
    н = наблюдатель if наблюдатель is not None else Наблюдение()
    точки = (
        (связность, 'доказательство_слоя', 'полное доказательство', None),
        (связность, 'полная_свежесть_основы', 'Markdown H', None),
        (связность, 'инвентарь_разметки', 'инвентарь Markdown W', None),
        (связность, 'проверить_слой_разметки', 'слой Markdown H/W', None),
        (связность, 'сверить_снимки_разметки', 'поздние снимки Markdown W', None),
        (связность, 'прочитать_разметку', 'безопасное чтение Markdown', _сырые),
        (связность, 'прочитать_обычный_файл', 'чтение обычного файла W', _сырые),
        (журнал, '_прочитать_объекты', 'пакет Git', _пакет),
        (свежесть, 'read_text', 'текстовое чтение recency', _текст),
        (свежесть, 'process_markdown_file', 'обработка Markdown', None),
        (свежесть, 'update_repository', 'полная проверка Markdown', None),
        (свежесть, 'стабильное_содержание_отчёта', 'нормализация отчёта', None),
        (Path, 'read_bytes', 'прямое чтение Path', _байты_path),
    )
    with contextlib.ExitStack() as стек:
        for объект, имя, роль, данные in точки:
            if hasattr(объект, имя):
                исходный = getattr(объект, имя)
                стек.enter_context(mock.patch.object(объект, имя,
                    н.обернуть(роль, исходный, данные)))
        yield н

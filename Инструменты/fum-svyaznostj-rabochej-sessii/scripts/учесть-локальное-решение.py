"""Явное чтение либо установка отдельного локального решения."""
import argparse
import json
import sys
from pathlib import Path

import локальные_решения_сообщений as слой


def главная(аргументы=None):
    разбор = argparse.ArgumentParser(allow_abbrev=False, description=__doc__)
    действия = разбор.add_subparsers(dest='действие', required=True)
    for имя in ('прочитать', 'сохранить'):
        команда = действия.add_parser(имя, allow_abbrev=False)
        команда.add_argument('--корень-репозитория', required=True)
        команда.add_argument('--исходник', required=True)
        команда.add_argument('--корневая-задача', required=True)
        команда.add_argument('--кэш')
        if имя == 'сохранить':
            команда.add_argument('--решение', required=True)
            команда.add_argument('--ожидаемая-локальная-история', required=True)
            команда.add_argument('--ожидаемая-обычная-история', required=True)
            команда.add_argument('--ожидаемый-читатель', required=True)
            команда.add_argument('--ожидаемый-классификатор', required=True)
            команда.add_argument('--допустимые-части-sha256', required=True)
    параметры = разбор.parse_args(аргументы)
    try:
        общие = dict(корень_репозитория=параметры.корень_репозитория, кэш=параметры.кэш)
        if параметры.действие == 'прочитать':
            итог = слой.прочитать_локальные_решения(параметры.исходник, параметры.корневая_задача, **общие)
        else:
            файл = Path(параметры.решение)
            слой.требовать(файл.is_absolute() and файл == файл.resolve(strict=True), 'нужен физический путь входа')
            запись = слой.читатель._разобрать(слой.штатная.прочитать_файл(файл))
            итог = слой.сохранить_локальное_решение(параметры.исходник, параметры.корневая_задача,
                **общие, запись=запись, ожидаемая_локальная_история=параметры.ожидаемая_локальная_история,
                ожидаемая_обычная_история=параметры.ожидаемая_обычная_история,
                ожидаемый_читатель=параметры.ожидаемый_читатель,
                ожидаемый_классификатор=параметры.ожидаемый_классификатор,
                допустимые_части_sha256=параметры.допустимые_части_sha256)
        print(json.dumps(итог, ensure_ascii=False, sort_keys=True))
        return 0
    except слой.НеизвестныйИсход:
        print('Исход установки неизвестен. Сохрани прежний вход и повтори только его.', file=sys.stderr)
        return 4
    except (OSError, ValueError, TypeError, KeyError):
        print('Локальное решение не подтверждено; входы и историю следует проверить.', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(главная())

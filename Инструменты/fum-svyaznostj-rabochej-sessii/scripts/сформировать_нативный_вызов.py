def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)

def поля(объект, имена):
    требовать(type(объект) is dict and set(объект) == set(имена), 'неверные закрытые поля')

def хэш(байты):
    return hashlib.sha256(байты).hexdigest()

def сумма(строка, длина=64):
    требовать(type(строка) is str and re.fullmatch('[0-9a-f]{' + str(длина) + '}', строка),
        'неверный полный идентификатор')
    return строка

def идентификатор(строка):
    требовать(type(строка) is str and str(uuid.UUID(строка)) == строка, 'нужен UUID')
    return строка

def байты(объект):
    return (json.dumps(объект, ensure_ascii=False, sort_keys=True, separators=(',', ':'),
        allow_nan=False) + '\n').encode()

def разобрать(данные):
    требовать(type(данные) is bytes and 0 < len(данные) <= ПРЕДЕЛ, 'неверный бюджет JSON')
    # Ограничение не зависит от реализации json.loads или sys.recursionlimit.
    глубина = 0; строка = False; экранирование = False
    for символ in данные:
        if строка:
            if экранирование: экранирование = False
            elif символ == 92: экранирование = True
            elif символ == 34: строка = False
        elif символ == 34: строка = True
        elif символ in (123, 91):
            глубина += 1
            требовать(глубина <= ПРЕДЕЛ_ГЛУБИНЫ, 'превышена глубина JSON')
        elif символ in (125, 93): глубина -= 1
    def пары(элементы):
        результат = {}
        for имя, значение in элементы:
            требовать(имя not in результат, 'повторный ключ')
            результат[имя] = значение
        return результат
    def константа(значение):
        raise ValueError('нечисловая константа')
    try:
        результат = json.loads(данные.decode('utf-8'), object_pairs_hook=пары, parse_constant=константа)
        байты(результат)
    except RecursionError as ошибка:
        raise ValueError('превышена глубина JSON') from ошибка
    return результат

def физический(строка, каталог=False):
    требовать(type(строка) is str and str(Path(строка)) == строка
        and Path(строка).is_absolute(), 'нужен абсолютный физический путь')
    путь = Path(строка)
    требовать(путь == путь.resolve(strict=True), 'алиас физического пути')
    родитель = Path(путь.anchor)
    for часть in путь.parts[1:]:
        требовать(часть in os.listdir(родитель), 'неверный регистр')
        родитель /= часть
        требовать(not stat.S_ISLNK(родитель.lstat().st_mode), 'symlink')
    требовать((stat.S_ISDIR if каталог else stat.S_ISREG)(путь.lstat().st_mode),
        'неверный тип физического пути')
    return путь

def отпечаток(состояние):
    return tuple(getattr(состояние, имя) for имя in ('st_dev', 'st_ino', 'st_mode',
        'st_uid', 'st_gid', 'st_nlink', 'st_size', 'st_mtime_ns', 'st_ctime_ns'))

class Удержанный:
    def __init__(сам, имя, ожидается=None, приватный=False, пустой=False):
        сам.путь = физический(str(имя))
        до = сам.путь.lstat()
        требовать(до.st_nlink == 1 and not stat.S_IMODE(до.st_mode) & 0o022, 'небезопасный файл')
        if приватный:
            требовать(до.st_uid == os.getuid() and stat.S_IMODE(до.st_mode) == 0o400,
                'нужен собственный mode0400')
        сам.личность = отпечаток(до)
        сам.дескриптор = os.open(сам.путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
        try:
            требовать((0 if пустой else 1) <= до.st_size <= ПРЕДЕЛ, 'превышен бюджет файла')
            сам.данные = os.pread(сам.дескриптор, до.st_size + 1, 0)
            сам.сверить()
            требовать(len(сам.данные) == до.st_size, 'короткое чтение')
            if ожидается is not None:
                требовать(хэш(сам.данные) == ожидается, 'не совпал выбранный SHA')
        except BaseException:
            сам.закрыть()
            raise
    def __enter__(сам):
        return сам
    def __exit__(сам, *ошибки):
        сам.закрыть()
    def сверить(сам):
        физический(str(сам.путь))
        требовать(отпечаток(сам.путь.lstat()) == отпечаток(os.fstat(сам.дескриптор))
            == сам.личность, 'удержанный файл дрейфовал')
        if hasattr(сам, 'данные'):
            требовать(os.pread(сам.дескриптор, len(сам.данные) + 1, 0) == сам.данные,
                'удержанные байты дрейфовали')
    def закрыть(сам):
        if сам.дескриптор is not None:
            os.close(сам.дескриптор)
            сам.дескриптор = None

def окружение(исполнитель):
    return {'PATH': os.defpath, 'CODEX_THREAD_ID': исполнитель,
        'GIT_OPTIONAL_LOCKS': '0', 'GIT_NO_LAZY_FETCH': '1'}

def гит(корень, *аргументы):
    ответ = subprocess.run(['git', '--no-optional-locks', '--no-replace-objects',
        '-C', str(корень), *аргументы], env=окружение(''), capture_output=True, timeout=120)
    требовать(ответ.returncode == 0, 'отказ чтения Git')
    return ответ.stdout

def проверить_выбор(выбор):
    поля(выбор, {'схема', 'версия', 'исполнитель', 'корень_кода', 'корень', 'коммит_кода',
        'файлы', 'Python', 'вход', 'поколение', 'ожидаемое_поколение', 'ключ', 'K', 'слот',
        'бюджет', 'операция'})
    требовать(выбор['схема'] == 'fum.выбор-нативной-подготовки.1' and выбор['версия'] == ВЕРСИЯ
        and выбор['операция'] == '--подготовить-запуск', 'чужая версия или операция')
    идентификатор(выбор['исполнитель'])
    физический(выбор['корень_кода'], True); физический(выбор['корень'], True)
    сумма(выбор['коммит_кода'], 40); сумма(выбор['K'], 40)
    требовать(type(выбор['файлы']) is list and len(выбор['файлы']) == len(СОСТАВ),
        'неполное замыкание')
    требовать([э['путь'] for э in выбор['файлы']] == list(СОСТАВ), 'чужой путь замыкания')
    for э in выбор['файлы']:
        поля(э, {'путь', 'blob', 'sha256', 'байты'})
        сумма(э['blob'], 40); сумма(э['sha256'])
        требовать(type(э['байты']) is int and 0 < э['байты'] <= ПРЕДЕЛ, 'неверная длина кода')
    поля(выбор['Python'], {'путь', 'sha256', 'личность'})
    сумма(выбор['Python']['sha256'])
    требовать(type(выбор['Python']['личность']) is list
        and len(выбор['Python']['личность']) == 9
        and all(type(э) is int and э >= 0 for э in выбор['Python']['личность']),
        'неверная личность Python')
    for имя in ('вход', 'поколение'):
        поля(выбор[имя], {'путь', 'sha256', 'личность'})
        требовать(type(выбор[имя]['личность']) is list and len(выбор[имя]['личность']) == 9
            and all(type(э) is int and э >= 0 for э in выбор[имя]['личность']),
            'неверная выбранная физическая личность')
        сумма(выбор[имя]['sha256']); физический(выбор[имя]['путь'])
    п = выбор['ожидаемое_поколение']
    поля(п, {'R', 'A', 'ACT', 'G', 'nonce', 'пауза'})
    for имя in ('R', 'A', 'ACT'): сумма(п[имя], 40)
    сумма(п['G']); идентификатор(п['nonce'])
    требовать(п['пауза'] is False, 'поколение на паузе')
    к = выбор['ключ']; поля(к, {'владелец', 'хэш_корня', 'ветка', 'R'})
    идентификатор(к['владелец']); сумма(к['хэш_корня']); сумма(к['R'], 40)
    требовать(к['хэш_корня'] == хэш(выбор['корень'].encode()) and к['R'] == п['R']
        and type(к['ветка']) is str and к['ветка'].startswith('refs/heads/'), 'чужой ключ')
    б = выбор['бюджет']; поля(б, {'подготовка_мс', 'exec_мс', 'ожиданий', 'ожидание_мс', 'токенов'})
    требовать(all(type(э) is int for э in б.values()) and 1 <= б['подготовка_мс'] <= 120000
        and 250 <= б['exec_мс'] <= 1000 and 0 <= б['ожиданий'] <= 10
        and 1000 <= б['ожидание_мс'] <= 5000 and 1000 <= б['токенов'] <= 8000
        and б['exec_мс'] + б['ожиданий'] * б['ожидание_мс'] <= 55000, 'неверный конечный бюджет')
    слот = Path(выбор['слот'])
    постоянные = {имя: к[имя] for имя in ('владелец','хэш_корня','ветка')}
    база = Path(выбор['корень']).parent / ('fum-приватная-нативная-подготовка-' + хэш(байты(постоянные)))
    требовать(str(слот) == выбор['слот'] and слот == база / п['R'],
        'слот должен быть фиксированным для W/ref/R; nonce не сбрасывает прежнее намерение')
    родитель = физический(str(слот.parent), True)
    с = родитель.lstat()
    требовать(с.st_uid == os.getuid() and stat.S_IMODE(с.st_mode) == 0o700, 'приватный родитель слота')
    for корень in (выбор['корень'], выбор['корень_кода']):
        гитдир = гит(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').decode().strip()
        требовать(not слот.is_relative_to(корень) and not слот.is_relative_to(гитдир),
            'слот попал в Git')
    return выбор

def удержать_выбор(имя, ожидаемый_хэш):
    сумма(ожидаемый_хэш)
    удержанные = {}
    try:
        удержанные['выбор'] = Удержанный(имя, ожидаемый_хэш, True)
        выбор = разобрать(удержанные['выбор'].данные)
        требовать(байты(выбор) == удержанные['выбор'].данные, 'неканонический выбор')
        проверить_выбор(выбор)
        корень = выбор['корень_кода']
        for э in выбор['файлы']:
            путь = str(Path(корень) / э['путь'])
            удержанные[э['путь']] = Удержанный(путь, э['sha256'])
            требовать(len(удержанные[э['путь']].данные) == э['байты'], 'длина кода')
            запись = гит(корень, 'ls-tree', '-z', выбор['коммит_кода'], '--', э['путь'])
            требовать(запись == ('100644 blob ' + э['blob'] + '\t' + э['путь']).encode() + b'\0',
                'путь не принадлежит принятому дереву')
            требовать(гит(корень, 'cat-file', 'blob', э['blob'])
                == удержанные[э['путь']].данные, 'код отличается от принятого blob')
        for имя in ('вход', 'поколение'):
            удержанные[имя] = Удержанный(выбор[имя]['путь'], выбор[имя]['sha256'], True)
            требовать(list(удержанные[имя].личность) == выбор[имя]['личность'],
                'выбранный вход или поколение заменены')
            требовать(байты(разобрать(удержанные[имя].данные)) == удержанные[имя].данные,
                'неканонические байты')
        вход = разобрать(удержанные['вход'].данные)
        поля(вход, {'схема', 'корень', 'каталог', 'контур', 'приёмка', 'акт', 'якорь',
            'подготовка_координатора'})
        п = выбор['ожидаемое_поколение']
        требовать(вход['схема'] == 'fum.вход-приёма-базиса-узла.2'
            and вход['корень'] == выбор['корень']
            and вход['приёмка']['коммит'] == п['A'] and вход['акт']['коммит'] == п['ACT'],
            'вход отличается от независимого выбора')
        требовать(разобрать(удержанные['поколение'].данные) == п, 'старое поколение или nonce')
        требовать(гит(выбор['корень'], 'symbolic-ref', 'HEAD').decode().strip() == выбор['ключ']['ветка']
            and гит(выбор['корень'], 'rev-parse', 'HEAD').decode().strip() == п['R'],
            'исходный ref/R дрейфовали')
        удержанные['Python'] = Удержанный(выбор['Python']['путь'], выбор['Python']['sha256'])
        требовать(list(удержанные['Python'].личность) == выбор['Python']['личность']
            and удержанные['Python'].личность[2] & 0o111, 'Python заменён')
        return выбор, удержанные
    except BaseException:
        for файл in удержанные.values(): файл.закрыть()
        raise

def пересверить(выбор, удержанные):
    for файл in удержанные.values(): файл.сверить()
    требовать(гит(выбор['корень'], 'rev-parse', 'HEAD').decode().strip()
        == выбор['ожидаемое_поколение']['R']
        and гит(выбор['корень'], 'symbolic-ref', 'HEAD').decode().strip() == выбор['ключ']['ветка'],
        'поколение отозвано')


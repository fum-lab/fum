def сформировать(имя, ожидаемый_хэш):
    выбор, удержанные = удержать_выбор(имя, ожидаемый_хэш)
    try:
        шаблон = удержанные[ШАБЛОН].данные.decode('utf-8')
        требовать(шаблон.endswith(';\n'), 'неверный конец CJS expression')
        ген = next(э for э in выбор['файлы'] if э['путь'] == ГЕНЕРАТОР)
        команда = ['/usr/bin/env', '-i', 'PATH=' + os.defpath,
            'CODEX_THREAD_ID=' + выбор['исполнитель'], 'GIT_OPTIONAL_LOCKS=0',
            'GIT_NO_LAZY_FETCH=1', выбор['Python']['путь'], '-I', '-S', '-B', '-c',
            НАЧАЛЬНЫЙ_ЗАГРУЗЧИК, str(удержанные['выбор'].путь), ожидаемый_хэш,
            str(удержанные[ГЕНЕРАТОР].путь), ген['sha256']]
        параметры = {'КОМАНДА': ' '.join(shlex.quote(э) for э in команда),
            'КОРЕНЬ': выбор['корень'], **{к: str(выбор['бюджет'][к]) for к in
            ('exec_мс', 'ожиданий', 'ожидание_мс', 'токенов')}}
        for имя_поля, значение in параметры.items():
            маркер = json.dumps('__' + имя_поля + '__', ensure_ascii=False)
            требовать(шаблон.count(маркер) == 1, 'неверное конечное поле шаблона')
            шаблон = шаблон.replace(маркер, json.dumps(значение, ensure_ascii=True), 1)
        требовать('__КОМАНДА__' not in шаблон and '__КОРЕНЬ__' not in шаблон, 'остаточный placeholder')
        пересверить(выбор, удержанные)
        return ОБЁРТКА_ДО + шаблон[:-2] + ОБЁРТКА_ПОСЛЕ
    finally:
        for файл in удержанные.values(): файл.закрыть()

def главный():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выбор', required=True)
    разбор.add_argument('--sha256', required=True)
    а = разбор.parse_args()
    try:
        sys.stdout.write(сформировать(а.выбор, сумма(а.sha256)))
        return 0
    except (ValueError,OSError,KeyError,TypeError,subprocess.SubprocessError) as о:
        print(str(о), file=sys.stderr)
        return 2

if __name__ == '__main__':
    raise SystemExit(главный())

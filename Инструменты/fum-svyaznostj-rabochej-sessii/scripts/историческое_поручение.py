def история(корень, запрос, г):
    """Старые форматы читаются без миграции и без записи нового запуска."""
    о = г.этап.коммит.отчёты
    _, файл, отчёт, каталог, относительный = о.разрешить_сессию(корень, запрос)
    записи = о.прочитать_историю_проверок(каталог, относительный) if os.path.lexists(каталог) else []
    return записи, {'схемы':list(dict.fromkeys(з['схема'] for _,з,_ in записи)),
        'активные':[з['идентификатор'] for _,з,_ in записи if з['состояние']!='завершён'],
        'закрыт':os.path.lexists(каталог/'снимок.json'),
        'переход':os.path.lexists(каталог/'возобновление.json'),
        'незаполнен':'<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->' in отчёт.read_text(),
        'запрос_sha256':г.хэш(файл.read_bytes()), 'отчёт_sha256':г.хэш(отчёт.read_bytes())}


def прочитать_сырые_записи(корень, выбранные, г, *, истории=None):
    г.требовать(type(выбранные) is list and выбранные, 'нужен конечный выбор исторических RAW')
    итог = {}
    прочитанные = dict(истории or {})
    for выбор in выбранные:
        г.поля(выбор, {'путь','sha256','режим'})
        имя = выбор['путь']
        г.требовать(type(имя) is str and имя not in итог, 'повтор исторического RAW')
        части = Path(имя).parts
        г.требовать(len(части)==5 and части[0]=='Журнал'
            and части[2:4]==('материалы','запуски-проверок')
            and части[4].endswith('.json'), 'неверный путь исторического RAW')
        файл = г.обычное.путь(корень, имя)
        запрос = (Path(*части[:2])/'запрос.md').as_posix()
        if запрос not in прочитанные:
            прочитанные[запрос] = история(корень, запрос, г)[0]
        записи = {п.relative_to(корень).as_posix():з for п,з,_ in прочитанные[запрос]}
        г.требовать(имя in записи and записи[имя]['состояние']=='завершён',
            'исторический RAW не является терминальной машинной записью')
        сведения = файл.lstat()
        г.требовать(stat.S_ISREG(сведения.st_mode) and сведения.st_nlink==1
            and type(выбор['режим']) is int and stat.S_IMODE(сведения.st_mode)==выбор['режим']
            and г.хэш(файл.read_bytes())==выбор['sha256'], 'подмена исторического RAW')
        итог[имя] = {'sha256':выбор['sha256'],'режим':выбор['режим']}
    return итог



def нативные_сведения(вход, решение, г):
    г.поля(вход['исполнитель'], {'задача','корень','источник_модели'})
    г.требовать(вход['исполнитель']=={'задача':вход['писатель'],'корень':вход['корень'],
        'источник_модели':вход['источник_модели']}, 'подмена исторического исполнителя')
    начало, контекст, граница = г.обычное.постановка.прочитать_начало_источника(вход['источник_модели'])
    поручение = г.обычное.постановка.прочитать_нативное_поручение(вход['источник_модели'],кодирование='буквальный')
    г.требовать(вход['писатель']!=решение['координатор'] and начало.get('id')==вход['писатель'] and начало.get('thread_source')=='agent_created_thread'
        and начало.get('cwd')==контекст.get('cwd')==вход['корень']
        and начало.get('git',{}).get('commit_hash')==вход['постановка']['коммит']
        and контекст.get('model')==решение['модель'] and контекст.get('effort')==решение['усилие']
        and поручение['отправитель']==решение['координатор'], 'подмена native исторического поручения')
    г.обычное.сверить_единый_снимок(Path(вход['источник_модели']),граница,поручение['источник'])
    return начало, контекст, {'исполнитель':вход['писатель'],'начало':граница,
        'поручение':поручение['источник'],'хэш_нативного_поручения':г.хэш(поручение['текст'].encode())}


def предпроверка(вход, г):
    """Готовность фактической пары без ACT; не возвращает M7 или установки."""
    г.поля(вход, ПОЛЯ-{'выбор_акта'})
    г.требовать(вход['схема']==СХЕМА_ПРЕДПРОВЕРКИ and вход['фаза']=='предпроверка',
        'неверный вход предпроверки')
    корень, снимок = г.собственное_дерево(вход)
    г.поля(вход['снимок'],{'HEAD','ref','индекс_sha256'})
    г.требовать(снимок==вход['снимок'],'дрейф исходного снимка предпроверки')
    каталог = г.этап.адреса.точный_абсолютный(вход['каталог_выходов'],приватный=True)
    сведения = каталог.lstat()
    г.требовать(stat.S_ISDIR(сведения.st_mode) and сведения.st_uid==os.getuid()
        and stat.S_IMODE(сведения.st_mode)==0o700,'нужен собственный private каталог0700')
    сырые, источник_решения = г.источник(корень,вход['решение'])
    решение = г.этап.коммит.сообщения._разобрать(сырые)
    г.проверить_решение(решение)
    г.требовать(решение['схема']=='fum.смысл-дочернего-поручения.1','нужен сохранённый recipe .1')
    г.требовать(решение['акт']['ветка']==снимок['ref'],'черновая ветка ACT не совпала с исполнителем')
    пост, источник_поста = г.источник(корень,вход['постановка'])
    г.сверить_постановку(решение,вход['постановка'],пост)
    _, _, нативный = нативные_сведения(вход,решение,г)
    г.поля(вход['журнал'],{'текущий','новый'})
    прежний, новый = (вход['журнал'][к] for к in ('текущий','новый'))
    рецепт = решение['подготовка']['исполнитель']
    г.требовать(новый==Path('Журнал',рецепт['журнал'],'запрос.md').as_posix(),
        'новый этап должен быть явно выбран ROOT')
    старые, старое = история(корень,прежний,г)
    новые, новое = история(корень,новый,г)
    г.требовать(not старое['активные'] and not старое['переход'],'исторический этап ещё меняется')
    г.требовать(not новое['активные'] and not новое['закрыт'] and not новое['переход']
        and all(с=='fum.test-run.v4' for с in новое['схемы']),'новому этапу нужна открытая v4-история')
    г.требовать('fum.test-run.v3' not in старое['схемы'] or прежний!=новый,
        'v3 остаётся исторической; ROOT должен выбрать новую пару')
    сохранённые = прочитать_сырые_записи(корень,вход['исторические_записи'],г,истории={прежний:старые})
    г.требовать(all(п.relative_to(корень).as_posix() in сохранённые for п,_,_ in старые),
        'неполный выбор RAW текущей исторической пары')
    команды = г.первичные_команды(вход,решение)
    г.этап.коммит.сверить_тексты({'корень':str(корень),'запрос':новый},команды)
    пара = поля_пары.проверить(корень,Path(новый))
    г.требовать(not пара['ошибки'],'пара до ACT не завершена: '+'; '.join(пара['ошибки']))
    навигация = поля_пары.связность.validate_navigation(корень,корень/новый,(корень/новый).read_text())
    г.требовать(not навигация,'навигация до ACT: '+'; '.join(навигация))
    г.требовать(type(рецепт['цели']) is list and рецепт['цели'] and all(type(п) is str for п in рецепт['цели']),
        'нужен конечный черновой состав ROOT')
    модель = Path(новый).parent.joinpath('материалы','история-модели.json').as_posix()
    обязательные = ['Индексы/markdown-файлы-по-времени-редактирования.md']
    if os.path.lexists(корень/модель):
        обязательные.append(модель)
    недостающие = [п for п in обязательные if п not in рецепт['цели']]
    г.требовать(not недостающие,'обязательная существующая цель не выбрана ROOT: '+', '.join(недостающие))
    курсор = г.этап.приватный(str(каталог/'кэш-модели.json'),существует=False)
    г.требовать(not os.path.lexists(курсор),'новый модельный курсор должен отсутствовать')
    разрешённые_записи = {*сохранённые,*[п.relative_to(корень).as_posix() for п,_,_ in новые]}
    цели = list(dict.fromkeys([*рецепт['цели'],*сохранённые,
        *[п.relative_to(корень).as_posix() for п,_,_ in новые],новый,str(Path(новый).with_name('отчёт.md'))]))
    г.обычное.проверить_область(корень,вход['область_писателя'],цели)
    г.обычное.проверить_область(корень,решение['акт']['область'],цели)
    г.требовать(all(not any(а=='материалы' and б=='запуски-проверок'
        for а,б in zip(Path(п).parts,Path(п).parts[1:])) or п in разрешённые_записи for п in цели),
        'невыбранный RAW в черновом составе')
    статус, _, изменённые = г.этап.коммит.охват.прочитать_статус(корень)
    недостающие = sorted(set(изменённые)-set(цели))
    г.требовать(not недостающие,'изменённые пути вне состава: '+', '.join(недостающие))
    публичные = {}; входы = {}
    имена = list(dict.fromkeys([*цели,прежний,str(Path(прежний).with_name('отчёт.md'))]))
    for имя in имена:
        файл = г.обычное.путь(корень,имя)
        сведения = файл.lstat()
        г.требовать(stat.S_ISREG(сведения.st_mode) and сведения.st_nlink==1,
            'черновая цель должна быть существующим обычным файлом')
        сырые = файл.read_bytes()
        входы[имя] = {'sha256':г.хэш(сырые),'режим':stat.S_IMODE(сведения.st_mode)}
        if имя in цели:
            публичные[имя] = сырые
    if модель not in входы:
        входы[модель] = {'тип':'отсутствует'}
    публикация = г.публикация(корень,публичные)
    г.поля(рецепт['наполнение'],{'инструменты','профиль','поля','вставки'})
    наполнение = {'задача':решение['координатор'],'запрос':новый,'ожидаемые_цели':[],**рецепт['наполнение']}
    имена_пары = (новый,str(Path(новый).with_name('отчёт.md')))
    отрендеренные = г.рендер.сформировать(*(публичные[п] for п in имена_пары),наполнение,цели,
        [(п.relative_to(корень).as_posix(),з,б) for п,з,б in новые],г.этап.коммит.отчёты,
        {п:{'тип':'файл'} for п in цели})
    оформление = dict(zip(имена_пары,отрендеренные,strict=True))
    ошибки = [о for п,б in оформление.items() for о in
        поля_пары.связность.проверить_незаполненный_маркер_шаблона(б.decode(),корень/п,корень)]
    г.требовать(not ошибки,'будущее оформление до ACT не завершено: '+'; '.join(ошибки))
    публикация_оформления = г.публикация(корень,оформление)
    время = рецепт['время']
    if '\n' in время:
        _, время = г.разобрать_время(время)
    обновления = {имя:{к:з for к,з in план.items() if к!='аргументы'} for имя,план in
        г.этап.план_обновлений({'обновления':решение['зависимости']},корень,цели,
            г.этап.свежесть.parse_display_time(время)).items()}
    композиция = г.снимок_композиции(вход,[],{'предпроверка':{'входы':входы},**обновления},сохранённые,новый)
    г.требовать(г.собственное_дерево(вход)[1]==снимок
        and г.этап.коммит.охват.прочитать_статус(корень)[0]==статус,'дрейф предпроверки')
    return {'схема':'fum.готовность-исторического-поручения.1','вход':вход,'снимок':снимок,
        'нативная_привязка':нативный,'истории':{'прежняя':старое,'новая':новое},
        'источники':{'решение':источник_решения,'постановка':источник_поста},
        'входы':входы,'композиция':композиция,'обновления':обновления,'поля_пары':пара,'публикация':публикация,
        'оформление':{п:г.хэш(б) for п,б in оформление.items()},'публикация_оформления':публикация_оформления,
        'статус_sha256':г.хэш(статус),'черновые_цели':цели,'не_разрешает_запись':True,'внешние_действия':[]}


def сверить_предпроверку(вход, г):
    выбор = вход['предпроверка']
    г.поля(выбор,{'путь','sha256'})
    файл = г.этап.приватный(выбор['путь'],режим=0o400)
    сырые = файл.read_bytes()
    г.требовать(г.хэш(сырые)==выбор['sha256'],'подмена предпроверки')
    прежняя = г.этап.коммит.сообщения._разобрать(сырые)
    ранний_вход = {к:з for к,з in вход.items() if к not in {'выбор_акта','предпроверка'}}
    ранний_вход.update(схема=СХЕМА_ПРЕДПРОВЕРКИ,фаза='предпроверка')
    г.требовать(предпроверка(ранний_вход,г)==прежняя,'дрейф предпроверки')
    return прежняя


def построить_план(вход, выбранный_акт, г):
    с_предпроверкой = вход.get('схема')==СХЕМА_С_ПРЕДПРОВЕРКОЙ
    г.поля(вход, ПОЛЯ|({'предпроверка'} if с_предпроверкой else set()))
    г.требовать(вход['схема'] in СХЕМЫ and вход['фаза']=='входы', 'неверная историческая фаза')
    ранний = сверить_предпроверку(вход, г) if с_предпроверкой else None
    г.требовать(type(выбранный_акт) is dict and выбранный_акт==вход['выбор_акта'],
        'нужен независимый выбор ACT')
    корень, снимок = г.собственное_дерево(вход)
    г.поля(вход['снимок'], {'HEAD','ref','индекс_sha256'})
    г.требовать(вход['снимок']==снимок, 'дрейф исходного снимка')
    каталог_выходов = г.этап.адреса.точный_абсолютный(вход['каталог_выходов'], приватный=True)
    состояние_каталога = каталог_выходов.lstat()
    г.требовать(stat.S_ISDIR(состояние_каталога.st_mode) and состояние_каталога.st_uid==os.getuid()
        and stat.S_IMODE(состояние_каталога.st_mode)==0o700, 'нужен собственный private каталог0700')
    сырые, сведения = г.источник(корень, вход['решение'])
    решение = г.этап.коммит.сообщения._разобрать(сырые)
    г.проверить_решение(решение)
    г.требовать(решение['схема']=='fum.смысл-дочернего-поручения.1',
        'исторический контракт требует отдельный сохранённый recipe .1')
    г.требовать(type(вход['источники']) is list and вход['источники']
        and all(type(и.get('экземпляры')) is list and и['экземпляры'] for и in вход['источники']),
        'ROOT-selected человеческие оригиналы обязательны')
    пост, сведения_поста = г.источник(корень, вход['постановка'])
    г.сверить_постановку(решение, вход['постановка'], пост)
    акт = г.обычное.прочитать_акт(корень, выбранный_акт)
    г.требовать(акт['координатор']==решение['координатор'] and акт['исполнитель']==вход['писатель']
        and акт['ветка']==снимок['ref'] and акт['постановка']==вход['постановка']
        and решение['акт']['путь']==выбранный_акт['путь']
        and решение['акт']['ветка']==акт['ветка'] and решение['акт']['область']==акт['область'],
        'историческое решение не совпало с независимым ACT')
    г.поля(вход['исполнитель'], {'задача','корень','источник_модели'})
    г.требовать(вход['исполнитель']=={'задача':вход['писатель'],'корень':str(корень),
        'источник_модели':вход['источник_модели']}, 'подмена исторического исполнителя')
    начало, контекст, нативный = нативные_сведения(вход, решение, г)
    граница = нативный['начало']
    г.требовать(нативный['хэш_нативного_поручения']==акт['хэш_нативного_поручения'],
        'подмена native исторического поручения')
    г.поля(вход['журнал'], {'текущий','новый'})
    прежний, новый = (вход['журнал'][к] for к in ('текущий','новый'))
    г.требовать(новый==Path('Журнал',решение['подготовка']['исполнитель']['журнал'],'запрос.md').as_posix(),
        'новый этап должен быть явно выбран ROOT')
    старые_записи, старое = история(корень, прежний, г)
    _, новое = история(корень, новый, г)
    г.требовать(not старое['активные'] and not старое['переход'], 'исторический этап ещё меняется')
    г.требовать(not новое['активные'] and not новое['закрыт'] and not новое['переход']
        and all(с=='fum.test-run.v4' for с in новое['схемы']), 'новому этапу нужна открытая v4-история')
    г.требовать('fum.test-run.v3' not in старое['схемы'] or прежний!=новый,
        'v3 остаётся исторической; ROOT должен выбрать новую пару')
    сохранённые = прочитать_сырые_записи(корень, вход['исторические_записи'], г, истории={прежний:старые_записи})
    г.требовать(all(п.relative_to(корень).as_posix() in сохранённые for п,_,_ in старые_записи),
        'неполный выбор RAW текущей исторической пары')
    тех, файлы, будущие, зависимости = г.технические_входы(вход, решение, снимок,
        выбранный_акт, нативный, сохранённые_записи=сохранённые)
    отчёт = будущие[str(Path(новый).with_name('отчёт.md'))].decode()
    содержание, число = re.subn(r'(?ms)^<!-- FUM-CHECK-RUNS:BEGIN[^\n]* -->\n.*?^<!-- FUM-CHECK-RUNS:END -->',
        '', отчёт)
    г.требовать(число==1 and '<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->' not in содержание,
        'новая пара не завершена до prepare')
    цели = тех['коммит']['разрешённые_цели']
    if ранний is not None:
        отложенные = {*тех['будущие_записи'],тех['коммит']['история_модели']}
        г.требовать(set(цели)==set(ранний['черновые_цели'])|отложенные,
            'M7 изменил существующие цели предпроверки')
    _, _, изменённые = г.этап.коммит.охват.прочитать_статус(корень)
    недостающие = sorted(set(изменённые)-set(цели))
    г.требовать(not недостающие, 'изменённые пути вне состава: '+', '.join(недостающие))
    разрешённые_записи = set(сохранённые)|set(тех['существующие_записи'])|set(тех['будущие_записи'])
    г.требовать(all(not any(а=='материалы' and б=='запуски-проверок'
        for а,б in zip(Path(п).parts,Path(п).parts[1:])) or п in разрешённые_записи for п in цели),
        'невыбранный RAW в конечном составе')
    г.этап.коммит.команды(тех['коммит'])
    допустимо_отсутствие = {*тех['будущие_записи'], тех['коммит']['история_модели']}
    входы = {}
    публичные = {}
    for имя in цели:
        файл = г.обычное.путь(корень, имя)
        if not os.path.lexists(файл):
            г.требовать(имя in допустимо_отсутствие, 'не существует выбранная цель: '+имя)
            входы[имя] = {'тип':'отсутствует'}
            continue
        сведения_файла = файл.lstat()
        г.требовать(stat.S_ISREG(сведения_файла.st_mode) and сведения_файла.st_nlink==1,
            'выбранная цель должна быть обычным файлом')
        публичные[имя] = файл.read_bytes()
        входы[имя] = {'sha256':г.хэш(публичные[имя]),'режим':stat.S_IMODE(сведения_файла.st_mode)}
    for запрос in dict.fromkeys((прежний, новый)):
        for имя in (запрос, str(Path(запрос).with_name('отчёт.md'))):
            входы[имя] = {'sha256':г.хэш((корень/имя).read_bytes()),'режим':stat.S_IMODE((корень/имя).stat().st_mode)}
    зависимости['историческая_пара'] = {'входы':входы}
    проверка = г.публикация(корень, {**публичные, **будущие})
    установки = [{'путь':str(Path(вход['каталог_выходов'])/имя), 'слой':'приватный','режим':0o600,
        'base64':base64.b64encode(г.байты(данные)).decode(), 'sha256':г.хэш(г.байты(данные))}
        for имя,данные in файлы.items()]
    for у in установки:
        файл = г.этап.приватный(у['путь'], существует=False)
        if os.path.lexists(файл):
            г.требовать(г.хэш(файл.read_bytes())==у['sha256'] and stat.S_IMODE(файл.stat().st_mode)==у['режим'],
                'коллизия исторических выходов')
    снимок['модель'] = граница
    снимок['основание_переноса'] = г.происхождение.проверить(вход, решение, снимок, начало, контекст, корень)
    снимок['композиция'] = г.снимок_композиции(вход, установки, зависимости,
        тех['снимок_существующих_записей'], новый, снимок['основание_переноса'])
    г.требовать(г.собственное_дерево(вход)[1]==вход['снимок'], 'дрейф предпросмотра')
    return {'схема':'fum.план-исторического-поручения.1', 'вход_sha256':г.хэш(г.байты(вход)),
        'снимок':снимок, 'источники':{'решение':сведения,'постановка':сведения_поста},
        'нативная_привязка':нативный, 'установка':установки, 'зависимости':зависимости,
        'публикация':проверка, 'технические_входы':тех, 'выбор_акта':выбранный_акт,
        'истории':{'прежняя':старое,'новая':новое}, 'внешние_действия':[]}


def применить(вход, файл_плана, ожидаемый_хэш, выбранный_акт, г):
    файл = г.этап.приватный(файл_плана, режим=0o400)
    сырые = файл.read_bytes()
    г.требовать(г.хэш(сырые)==ожидаемый_хэш, 'подмена плана исторического поручения')
    план = г.этап.коммит.сообщения._разобрать(сырые)
    г.требовать(построить_план(вход, выбранный_акт, г)==план, 'дрейф исторического плана')
    установлены = []
    for у in план['установка']:
        г.сверить_границу_установки(вход, план)
        цель = г.этап.приватный(у['путь'], существует=False)
        данные = base64.b64decode(у['base64'], validate=True)
        г.требовать(г.хэш(данные)==у['sha256'], 'подмена байтов исторического плана')
        if not os.path.lexists(цель):
            д = os.open(цель, os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW, у['режим'])
            with os.fdopen(д,'wb') as поток:
                os.fchmod(поток.fileno(),у['режим'])
                поток.write(данные); поток.flush(); os.fsync(поток.fileno())
        г.требовать(цель.read_bytes()==данные and stat.S_IMODE(цель.stat().st_mode)==у['режим'],
            'частичная историческая установка требует readback')
        установлены.append(у['путь'])
    г.требовать(построить_план(вход, выбранный_акт, г)==план, 'дрейф после исторической установки')
    return {'установлены':установлены,'частичный_результат_сохраняется':True,'внешние_действия':[]}

"""Явная сверка полного прежнего префикса перед сменой inode JSONL."""
import os
import re
import time
import uuid
from contextlib import nullcontext
from pathlib import Path

import история_модели as модель


чтение = модель.чтение
_ХЭШ = re.compile(r"[0-9a-f]{64}\Z")


def прочитать_подтверждённую_историю(задача, курсор, назначение):
    """Принять только устойчивую полную пару истории и приватного курсора."""
    чтение._требовать(назначение.exists() and курсор.exists(), "нужны существующие история и курсор")
    старые_байты = модель._прочитать(назначение)
    оболочка = чтение._разобрать(модель._прочитать(курсор, True))
    чтение._требовать(type(оболочка) is dict and set(оболочка) == {"данные", "sha256"}, "неверный курсор")
    прежний = оболочка["данные"]
    чтение._требовать(type(прежний) is dict and
        чтение._хэш(чтение._байты(прежний)) == оболочка["sha256"], "повреждённый курсор")
    чтение._требовать(set(прежний) == {"история", "метка", "назначение", "реализация",
        "ожидаемый_sha256", "подготовлено"}, "неверная схема курсора")
    прежняя_история = прежний["история"]
    чтение._требовать(type(прежняя_история) is dict and
        прежний["назначение"] == str(назначение) and
        прежняя_история.get("задача") == задача and
        прежняя_история.get("схема") == модель._СХЕМА, "чужой или повреждённый курсор")
    чтение._требовать(прежний["реализация"] == модель._РЕАЛИЗАЦИЯ,
        "реализация изменилась; нужна отдельная миграция истории")
    чтение._требовать(прежний["подготовлено"] is False and прежний["ожидаемый_sha256"] is None,
        "идёт незавершённая транзакция; сначала восстановите обычным импортом")
    метка = прежний["метка"]
    чтение._требовать(type(метка) is list and len(метка) == 5 and
        all(type(значение) is int for значение in метка), "повреждена метка прежнего источника")
    чтение._требовать(set(прежняя_история) == {"схема", "задача", "источник", "граница",
        "sha256", "число_наблюдений", "события", "пропуски", "последнее",
        "переключения_между_наблюдениями_известны", "размер_снимка", "неполный_хвост"} and
        type(прежняя_история["число_наблюдений"]) is int and
        прежняя_история["число_наблюдений"] >= 0 and
        type(прежняя_история["события"]) is list and
        type(прежняя_история["пропуски"]) is list and
        type(прежняя_история["переключения_между_наблюдениями_известны"]) is bool and
        isinstance(прежняя_история["источник"], str) and
        _ХЭШ.fullmatch(прежняя_история["источник"]) is not None,
        "повреждена история в курсоре")
    размер = прежняя_история.get("размер_снимка")
    граница = прежняя_история.get("граница")
    чтение._требовать(type(размер) is int and type(граница) is int and
        размер == граница == метка[2] and прежняя_история.get("неполный_хвост") == 0 and
        isinstance(прежняя_история.get("sha256"), str) and
        _ХЭШ.fullmatch(прежняя_история["sha256"]) is not None,
        "старый снимок неполон или не совпадает с курсором")
    чтение._требовать(старые_байты == чтение._байты(прежняя_история),
        "история не совпадает с курсором; нужна сверка")
    return старые_байты, прежний, прежняя_история, метка


def перепривязать(источник, задача, *, корень_репозитория, кэш, история, без_записи=False):
    """Перепроверить неизменный полный префикс и сохранить новый курсор.

    Обычный импорт сохраняет строгий отказ при замене inode. Эту процедуру
    вызывают явно только после отдельной сверки прежнего полного снимка.
    """
    начало = time.perf_counter_ns()
    чтение._требовать(str(uuid.UUID(задача)) == задача, "неканонический UUID")
    корень = модель._путь(корень_репозитория)
    исходник, курсор, назначение = map(модель._путь, (источник, кэш, история))
    чтение._требовать(назначение.is_relative_to(корень), "история вне своего checkout")
    чтение._требовать(not курсор.is_relative_to(корень) and not any(
        os.path.lexists(предок / ".git") for предок in курсор.parents), "курсор должен быть вне Git")
    чтение._требовать(len({исходник, курсор, назначение}) == 3, "совпадающие пути")
    чтение._требовать(курсор.parent.is_dir() and назначение.parent.is_dir(), "родительский каталог отсутствует")

    with nullcontext() if без_записи else чтение._замок(курсор):
        старые_байты, прежний, прежняя_история, метка = прочитать_подтверждённую_историю(
            задача, курсор, назначение)

        профиль = {"прочитано_байтов": 0, "разобрано_строк": 0}
        начало_чтения = time.perf_counter_ns()
        with os.fdopen(os.open(исходник, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
            состояние = os.fstat(поток.fileno())
            чтение._обычный(состояние)
            чтение._требовать(метка[:2] != чтение._метка(состояние)[:2],
                "источник не был заменён; используйте обычный импорт")
            данные = модель._приём(поток, задача, прежняя_история, состояние.st_size, профиль)
            дописано, перепроверено = чтение._сверить_снимок(поток, исходник, состояние, данные)
            профиль["прочитано_байтов"] += перепроверено
        профиль["чтение_наносекунды"] = time.perf_counter_ns() - начало_чтения

        новые_байты = чтение._байты(данные)
        новое = {"история": данные, "метка": чтение._метка(состояние),
            "назначение": str(назначение), "реализация": модель._РЕАЛИЗАЦИЯ,
            "подготовлено": False, "ожидаемый_sha256": None}
        начало_записи = time.perf_counter_ns()
        if not без_записи:
            if старые_байты != новые_байты:
                подготовленное = {**новое, "подготовлено": True,
                    "ожидаемый_sha256": чтение._хэш(старые_байты)}
                чтение._установить(курсор, чтение._байты({"данные": подготовленное,
                    "sha256": чтение._хэш(чтение._байты(подготовленное))}))
                чтение._установить(назначение, новые_байты)
            if прежний != новое:
                чтение._установить(курсор, чтение._байты({"данные": новое,
                    "sha256": чтение._хэш(чтение._байты(новое))}))
        профиль["сохранение_наносекунды"] = time.perf_counter_ns() - начало_записи
        профиль["всего_наносекунды"] = time.perf_counter_ns() - начало
        return {"схема": "fum.перепривязка-истории-модели.1", "задача": задача,
            "новых_наблюдений": данные["число_наблюдений"] - прежняя_история["число_наблюдений"],
            "число_наблюдений": данные["число_наблюдений"], "событий": len(данные["события"]),
            "пропусков": len(данные["пропуски"]), "последнее": данные["последнее"],
            "неполный_хвост": данные["неполный_хвост"], "дописано_после_снимка": дописано,
            "полнота": not данные["пропуски"] and not данные["неполный_хвост"] and not дописано,
            "переключения_между_наблюдениями_известны": False,
            "история_sha256": чтение._хэш(новые_байты),
            "изменения_нужны": старые_байты != новые_байты or прежний != новое,
            "перепривязка": True, "без_записи": без_записи, "профиль": профиль}

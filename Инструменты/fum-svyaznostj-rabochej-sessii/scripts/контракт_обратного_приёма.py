"""Чистый план обратного приёма; подлинность входов проверяет вызывающий адаптер.

План не разрешает запись. Ревью выбирается принимающей стороной вне кандидата.
Эта версия переносит только проверки дерева; прочие зависимости требуют
отдельного порядка проверки после слияния.
"""
import hashlib
import json
import re
import uuid


def _поля(значение, поля, имя):
    if type(значение) is not dict or set(значение) != set(поля.split()):
        raise ValueError(f"{имя}: неподдержанный состав полей")
    return значение


def _текст(значение, имя):
    if type(значение) is not str or not значение or any(ord(символ) < 32 for символ in значение):
        raise ValueError(f"{имя}: требуется непустой текст")
    return значение


def _отпечаток(значение, длина, имя):
    if type(значение) is not str or re.fullmatch(f"[0-9a-f]{{{длина}}}", значение) is None:
        raise ValueError(f"{имя}: неверный отпечаток")
    return значение


def _схема(значение, схема):
    if значение["схема"] != схема:
        raise ValueError(f"Неподдержанная схема: ожидалась {схема}")


def _идентификатор(значение):
    _текст(значение, "координатор")
    try:
        if str(uuid.UUID(значение)) != значение:
            raise ValueError()
    except (ValueError, AttributeError):
        raise ValueError("координатор: неверный UUID") from None


def _ветка(значение, имя):
    _поля(значение, "ветка коммит дерево", имя)
    ссылка = _текст(значение["ветка"], имя)
    if (not ссылка.startswith("refs/heads/") or ссылка.endswith(("/", "."))
            or any(символ in ссылка for символ in " \x7e^:?*[\\\x7f")
            or any(компонент in ссылка for компонент in ("..", "@{", "//"))
            or any(компонент.startswith(".") or компонент.endswith(".lock") for компонент in ссылка.split("/"))):
        raise ValueError(f"{имя}: нужен полный ref ветки")
    _отпечаток(значение["коммит"], 40, имя)
    _отпечаток(значение["дерево"], 40, имя)


def _массив(значение, имя):
    if type(значение) is not list:
        raise ValueError(f"{имя}: требуется массив")
    return значение


def _имена(значение, имя):
    _массив(значение, имя)
    for элемент in значение:
        _текст(элемент, имя)
    if len(set(значение)) != len(значение):
        raise ValueError(f"{имя}: повтор идентификатора")
    return значение


def _объект(пары):
    объект = {}
    for ключ, значение in пары:
        if ключ in объект:
            raise ValueError(f"JSON: повтор ключа {ключ}")
        объект[ключ] = значение
    return объект


def _недопустимая_константа(значение):
    raise ValueError(f"JSON: недопустимая константа {значение}")


def _читать(сырые, отпечаток, имя):
    _отпечаток(отпечаток, 64, имя)
    if type(сырые) is not bytes:
        raise ValueError(f"{имя}: требуются исходные байты")
    if hashlib.sha256(сырые).hexdigest() != отпечаток:
        raise ValueError(f"{имя}: SHA не совпал")
    try:
        return json.loads(сырые.decode("utf-8"), object_pairs_hook=_объект,
                          parse_constant=_недопустимая_константа)
    except (UnicodeError, json.JSONDecodeError) as ошибка:
        raise ValueError(f"{имя}: неверный JSON") from ошибка


def составить_план(заявка, наблюдение, ревью, проверки):
    """Проверить точные привязки и вернуть воспроизводимый план без эффекта."""
    _поля(заявка, "схема координатор получатель источник ревью_sha256 проверки", "заявка")
    _схема(заявка, "fum.заявка-обратного-приёма.1")
    _идентификатор(заявка["координатор"])
    _поля(наблюдение, "схема координатор получатель источник разница_sha256 "
           "основа_является_предком рабочее_дерево_чисто "
           "ревью_из_принимающего_дерева операции_git", "наблюдение")
    _схема(наблюдение, "fum.наблюдение-обратного-приёма.1")
    if наблюдение["координатор"] != заявка["координатор"]:
        raise ValueError("Не совпал координатор")
    for имя in ("получатель", "источник"):
        _ветка(заявка[имя], имя)
        _ветка(наблюдение[имя], имя)
        if заявка[имя] != наблюдение[имя]:
            raise ValueError(f"Изменился {имя}")
    основа, кандидат = заявка["получатель"]["коммит"], заявка["источник"]["коммит"]
    дерево = заявка["источник"]["дерево"]
    if заявка["получатель"]["ветка"] == "refs/heads/master":
        raise ValueError("Специальный маршрут master здесь не поддержан")
    if основа == кандидат or заявка["получатель"]["ветка"] == заявка["источник"]["ветка"]:
        raise ValueError("Нужны разные коммиты и ветки")
    for поле in ("основа_является_предком", "рабочее_дерево_чисто",
                 "ревью_из_принимающего_дерева"):
        if наблюдение[поле] is not True:
            raise ValueError(f"Не подтверждено: {поле}")
    if _массив(наблюдение["операции_git"], "операции_git"):
        raise ValueError("Уже существует операция Git")
    _отпечаток(наблюдение["разница_sha256"], 64, "diff")

    решение = _читать(ревью, заявка["ревью_sha256"], "ревью")
    _поля(решение, "схема координатор основа кандидат дерево разница_sha256 решение "
           "охват проверки переносимые_проверки", "ревью")
    _схема(решение, "fum.решение-ревью-обратного-приёма.1")
    ожидаемые = {"координатор": заявка["координатор"], "основа": основа, "кандидат": кандидат,
                 "дерево": дерево, "разница_sha256": наблюдение["разница_sha256"],
                 "решение": "принять", "охват": "полное-изменение"}
    for ключ, значение in ожидаемые.items():
        if решение[ключ] != значение:
            raise ValueError(f"Ревью: не совпало поле {ключ}")

    выбранные = _массив(заявка["проверки"], "проверки")
    _массив(проверки, "байты проверок")
    if not выбранные or len(проверки) != len(выбранные):
        raise ValueError("Неполный или лишний набор проверок")
    имена = []
    for выбранная in выбранные:
        _поля(выбранная, "идентификатор sha256", "выбранная проверка")
        имена.append(_текст(выбранная["идентификатор"], "идентификатор"))
        _отпечаток(выбранная["sha256"], 64, "проверка")
    _имена(имена, "проверки")
    if _имена(решение["проверки"], "проверки ревью") != имена:
        raise ValueError("Ревью не связывает весь выбранный набор проверок")
    if _имена(решение["переносимые_проверки"], "переносимые проверки") != имена:
        raise ValueError("Ревью не подтвердило переносимость всех проверок")
    for выбранная, сырые in zip(выбранные, проверки, strict=True):
        результат = _читать(сырые, выбранная["sha256"], "проверка")
        _поля(результат, "схема идентификатор кандидат дерево статус код завершён "
               "зависимости", "результат проверки")
        _схема(результат, "fum.свидетельство-переносимой-проверки.1")
        if (результат["идентификатор"] != выбранная["идентификатор"]
                or результат["кандидат"] != кандидат or результат["дерево"] != дерево):
            raise ValueError("Проверка не соответствует выбранному кандидату и дереву")
        if (результат["статус"] != "успешно" or type(результат["код"]) is not int
                or результат["код"] != 0 or результат["завершён"] is not True):
            raise ValueError("Нет успешного завершения проверки")
        if результат["зависимости"] != ["дерево"]:
            raise ValueError("Неподдержанная переносимость проверки")

    return {"схема": "fum.план-обратного-приёма.1",
            "координатор": заявка["координатор"],
            "ветка": заявка["получатель"]["ветка"],
            "получатель": dict(заявка["получатель"]),
            "источник": dict(заявка["источник"]), "родители": [основа, кандидат], "дерево": дерево,
            "разница_sha256": наблюдение["разница_sha256"],
            "ревью_sha256": заявка["ревью_sha256"],
            "проверки": [dict(выбранное_значение) for выбранное_значение in выбранные],
            "повторный_полный_прогон": False, "разрешение_записи": False}

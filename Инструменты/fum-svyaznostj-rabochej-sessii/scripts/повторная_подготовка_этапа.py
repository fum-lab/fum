def выбранный(адрес, *, режим=0o600):
    требовать(type(адрес) is dict and set(адрес)=={'путь','sha256'}, 'неверный выбранный адрес')
    файл=фасад.приватный(адрес['путь'],режим=режим)
    сырые=файл.read_bytes()
    требовать(type(адрес['sha256']) is str and хэш(сырые)==адрес['sha256'], 'подмена raw SHA выбранного входа')
    return файл,коммит.сообщения._разобрать(сырые)


def манифест(корень,запрос):
    _,записи=фасад.история(корень,запрос)
    return [{'путь':п.relative_to(корень).as_posix(),'идентификатор':з['идентификатор'],
        'порядок':з['порядок'],'sha256':хэш(сырые),'режим':stat.S_IMODE(п.lstat().st_mode)}
        for п,з,сырые in записи]


def контур(п,старый_вход,старый_план):
    выбран=старый_вход.get('контур','слияние')
    требовать(выбран in {'обычный','слияние'} and ('контур' not in старый_вход or выбран=='обычный'),
        'неизвестный сохранённый ROOT контур')
    обычный=выбран=='обычный'
    требовать(старый_план['контур']==('корневой-обычный' if обычный else 'root5')
        and старый_план['снимок']['родители']==п['родители']
        and старый_план['снимок']['HEAD']==п['исходный_коммит']
        and старый_план['снимок']['ref']==п['ветка'], 'противоречивый сохранённый ROOT контур')
    фасад.проверить_корневой_контур(п,Path(п['корень']),обычный)
    return выбран


def построить_план(вход):
    требовать(type(вход) is dict and set(вход)==ПОЛЯ
        and вход['схема']=='fum.повторная-подготовка-ROOT.1', 'неверные поля повторного ROOT входа')
    файл_подготовки,подготовка=выбранный(вход['прежняя_подготовка'])
    требовать(type(подготовка) is dict and set(подготовка)==ПОЛЯ_ПОДГОТОВКИ
        and подготовка['схема']=='fum.подготовленный-коммит.7', 'нужна сохранённая ROOT .5 подготовка')
    п=подготовка['параметры']
    требовать(type(п) is dict and set(п)==коммит.ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ
        and п['схема']=='fum.создание-коммита.5' and п['режим']=='контрольная-точка', 'неверная исходная ROOT .5')
    корень=фасад.адреса.проверить_пути(п)
    файл_готовности=коммит.готовность.путь_этапа(п)
    требовать(подготовка['готовность']==str(файл_готовности)
        and вход['отзыв_готовности']['путь']==str(файл_готовности), 'чужой адрес отзыва')
    выбранный(вход['отзыв_готовности'])
    готовность=коммит.готовность.прочитать(файл_готовности,п)
    требовать(готовность['корень']==str(корень) and готовность['активное'] is None
        and готовность['отзывы'][-1]['поколение']==len(готовность['поколения'])-1,
        'нужен действительный явный отзыв последнего поколения')
    поколение=len(готовность['поколения'])-1
    # Ключ назначения stock готовности + поколение, независимо от упаковки
    # подготовки, caller outputs и меняющегося максимального возраста отзыва.
    полный=файл_готовности.with_name(файл_готовности.stem+f'.повтор-{поколение}.json')
    фасад.приватный(полный,существует=False)
    требовать(not os.path.lexists(полный), 'занят полный результат; повтор эффекта запрещён')
    файл_входа,старый=выбранный(вход['прежний_вход'])
    файл_плана,прежний=выбранный(вход['прежний_план'],режим=0o400)
    требовать(type(старый) is dict and 'начало' in старый and старый['повтор'] is False
        and прежний['вход_sha256']==хэш(байты(старый)), 'не связан сохранённый ROOT фасад')
    старые_п=фасад.приватный(старый['вход_коммита'])
    требовать(фасад.прочитать(старые_п)==п
        and хэш(старые_п.read_bytes())==прежний['снимок']['файлы'][str(старые_п)]['sha256'],
        'подмена исходных параметров подготовки')
    требовать(п['подготовка']==str(файл_подготовки) and подготовка['команды']==прежний['команды'],
        'сохранённая подготовка относится к другому плану')
    вид=контур(п,старый,прежний)
    время=фасад.свежесть.parse_display_time(старый['время'])
    требовать(фасад.свежесть.format_msk(время)==старый['время'], 'подмена времени повторного этапа')
    наполнение=фасад.прочитать(старый['наполнение'])
    разрешение=фасад.приватный(наполнение['разрешение']['путь'])
    требовать(наполнение['задача']==п['задача'] and наполнение['запрос']==п['запрос']
        and фасад.прочитать(разрешение)==п['разрешённые_цели']
        and хэш(разрешение.read_bytes())==наполнение['разрешение']['sha256']
        and хэш(Path(старый['наполнение']).read_bytes())==прежний['снимок']['файлы'][старый['наполнение']]['sha256'],
        'подмена прежнего fill или разрешения')
    старые_запуски=манифест(корень,п['запрос'])
    свидетельства=[[э['идентификатор'],э['sha256']] for э in старые_запуски]
    требовать(свидетельства[:len(готовность['поколения'][-1]['записи'])]==готовность['поколения'][-1]['записи'],
        'переписаны подтверждённые v4')
    первичный=готовность['поколения'][0]['снимок']
    назначение=коммит.готовность.снимок(п,подготовка['команды'],первичный['проверки'],
        {'содержимое':'sha256:'+первичный['отпечаток_содержимого']})
    требовать(коммит.готовность.поколения.граница(назначение)==коммит.готовность.поколения.граница(первичный),
        'не совпадает прежняя постановка готовности')
    требовать(старый['готовность']=={'проверки':первичный['проверки'],'предел_секунд':готовность['предел_секунд']},
        'не совпадает исходный выбранный ready контур')
    _,фактические=фасад.история(корень,п['запрос'])
    по_идентификаторам={з['идентификатор']:(ф,з) for ф,з,_ in фактические}
    for проверка in старый['проверки']:
        ф,з=по_идентификаторам[проверка['идентификатор']]
        требовать(з['порядок']==проверка['порядок'] and з['сессия']==п['запрос']
            and з['вызов']==проверка['название'] and з['профиль_проверки']['класс']==проверка['класс']
            and ф.relative_to(корень).as_posix() in прежний['будущие_цели'], 'не совпадает сохранённый рецепт с v4')
    требовать([э['идентификатор'] for э in старый['проверки']]+[старый['связность']['идентификатор']]==первичный['проверки'],
        'переставлены исходные v4 UUID')
    курсор=фасад.приватный(п['кэш_модели'])
    фасад.проверить_назначение_курсора(п,корень)
    сырая_история=коммит.прочитать(корень/п['история_модели'])
    сохранённая=коммит.сообщения._разобрать(сырая_история)
    модель,_,_=наблюдать_сохранённую(п,коммит.прочитать,коммит.наблюдать_модель)
    требовать(хэш(сырая_история)==подготовка['история_sha256']
        and сохранённая['число_наблюдений']==подготовка['наблюдений']
        and модель['последнее']==подготовка['модель']
        and коммит.команды(п)==подготовка['команды'], 'дрейф модели, истории или выбранных команд')
    выходы=вход['новые_выходы']
    требовать(type(выходы) is dict and set(выходы)==ВЫХОДЫ, 'неполный перечень новых private outputs')
    пути=[фасад.приватный(выходы[к],существует=False,режим=0o400 if к=='план_наполнения' else 0o600)
        for к in sorted(ВЫХОДЫ)]
    защищаемые={файл_подготовки,файл_входа,файл_плана,файл_готовности,старые_п,
        Path(старый['наполнение']),разрешение,курсор,Path(п['источник_модели']),полный}
    защищаемые.update(Path(э['путь']) for э in п['источники'])
    защищаемые.update(Path(э['кэш']) for э in п['источники'] if 'кэш' in э)
    требовать(len(set(пути))==len(пути) and not set(пути)&защищаемые
        and not any(os.path.lexists(ф) for ф in пути), 'новые outputs заняты или пересекают старые роли')
    номера=вход['новые_проверки']; обязательные=готовность['поколения'][-1]['снимок']['проверки']
    требовать(type(номера) is list and len(номера)==len(старый['проверки'])+1==len(обязательные)
        and len(set(номера))==len(номера)
        and all(type(и) is str and str(uuid.UUID(и))==и for и in номера)
        and not set(номера)&{э['идентификатор'] for э in старые_запуски}, 'неверные выбранные новые UUID')
    номер=max((э['порядок'] for э in старые_запуски),default=0)+1
    каталог=Path(п['запрос']).parent/'материалы/запуски-проверок'
    будущие=[(каталог/f'{н}_{и}.json').as_posix() for н,и in enumerate(номера,номер)]
    for ц in будущие: требовать(not os.path.lexists(корень/ц),'future запись уже существует')
    старые_цели={э['путь'] for э in старые_запуски}
    цели=[]
    for ц in п['разрешённые_цели']:
        if коммит.готовность.поколения.номер_запуска(готовность['поколения'][0]['снимок'],ц) is not None:
            if ц in старые_цели: цели.append(ц)
        else:
            требовать(os.path.lexists(коммит.охват.точный_путь(корень,ц)), 'не-v4 цель исчезла')
            цели.append(ц)
    цели+=sorted(старые_цели-set(цели)); цели+=будущие
    _,_,грязные=коммит.охват.прочитать_статус(корень)
    требовать(set(грязные)<=set(цели), 'dirty путь вне разрешения повторного ROOT')
    новые_п=copy.deepcopy(п)
    новые_п.update({к:выходы[к] for к in ('сообщение','подготовка','квитанция')})
    новые_п['разрешённые_цели']=цели
    новое_нап=copy.deepcopy(наполнение)
    новое_нап['разрешение']={'путь':выходы['разрешение'],'sha256':хэш(байты(цели))}
    новое_нап['ожидаемые_цели']=будущие
    проверки=copy.deepcopy(старый['проверки'])
    for н,и,проверка in zip(range(номер,номер+len(проверки)),номера,проверки):
        требовать(set(проверка)=={'идентификатор','порядок','название','класс','аргументы'}
            and проверка['аргументы']==прежний['аргументы_проверок'][н-номер], 'подмена выбранной проверки')
        проверка.update(идентификатор=и,порядок=н)
    новый_фасад={'вход_коммита':выходы['вход_коммита'],'наполнение':выходы['наполнение'],
        'план_наполнения':выходы['план_наполнения'],'время':старый['время'],'повтор':True,
        'контур':вид,'проверки':проверки,'связность':{'идентификатор':номера[-1],'порядок':номер+len(проверки)},
        'готовность':{'проверки':номера,'предел_секунд':готовность['предел_секунд']}}
    файлы={}
    наблюдаемые=защищаемые-{Path(п['источник_модели']),полный}
    наблюдаемые-={Path(э['путь']) for э in п['источники']}
    наблюдаемые.update(корень/ц for ц in цели)
    for ф in sorted(наблюдаемые):
        if os.path.lexists(ф):
            с=ф.lstat(); требовать(stat.S_ISREG(с.st_mode),'необычный файл снимка повторного ROOT')
            файлы[str(ф)]={'sha256':хэш(ф.read_bytes()),'режим':stat.S_IMODE(с.st_mode)}
        else: файлы[str(ф)]=None
    файлы[str(курсор)]={'sha256':хэш(курсор.read_bytes()),'режим':0o600}
    файлы[str(корень/п['история_модели'])]={'sha256':хэш(сырая_история),
        'режим':stat.S_IMODE((корень/п['история_модели']).stat().st_mode)}
    индекс=Path(фасад.поручения._гит(корень,'rev-parse','--path-format=absolute','--git-path','index'))
    слияние=Path(фасад.поручения._гит(корень,'rev-parse','--absolute-git-dir'))/'MERGE_HEAD'
    return {'схема':'fum.план-повторной-подготовки-ROOT.1','вход_sha256':хэш(байты(вход)),
        'контур':вид,'поколение':поколение,'полный_результат':str(полный),
        'новый_вход_фасада':выходы['вход_фасада'],
        'замены':dict(zip(обязательные,номера)),'следующий_номер':номер,'манифест':старые_запуски,
        'неизменные_входы':sorted(map(str,{файл_подготовки,файл_входа,файл_плана,старые_п,
            Path(старый['наполнение']),разрешение})),
        'отозванная_готовность':{'путь':str(файл_готовности),'sha256':вход['отзыв_готовности']['sha256'],
            'поколения':готовность['поколения'],'отзывы':готовность['отзывы']},
        'готовность':{'готов_в_наносекундах_эпохи':готовность['готов_в_наносекундах_эпохи'],
            'предел_секунд':готовность['предел_секунд']},'будущие_цели':будущие,
        'команды':подготовка['команды'],'модель':подготовка['модель'],
        'технические_входы':{'коммит':новые_п,'наполнение':новое_нап,'разрешение':цели,'фасад':новый_фасад},
        'снимок':{'HEAD':п['исходный_коммит'],'ref':п['ветка'],'родители':п['родители'],
            'MERGE_HEAD':хэш(слияние.read_bytes()) if os.path.lexists(слияние) else None,
            'индекс_sha256':хэш(индекс.read_bytes()),'файлы':файлы},
        'обновления':фасад.план_обновлений({'обновления':['журнал','recency']},корень,цели,время)}



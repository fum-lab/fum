def проверить_время(событие, корень, исполнитель):
    """Только завершённый собственный прямой CLI, без shell/--at/даты ROOT."""
    import подготовка_дочернего_поручения as генератор
    требовать=основание.требовать
    корень=Path(корень)
    требовать(основание.известный_служебный_хвост(событие,исполнитель),'неподдержанная транспортная оболочка времени')
    требовать(type(событие) is dict and событие.get('type')=='event_msg','нет native события времени')
    данные=событие.get('payload',{})
    требовать(type(данные) is dict and данные.get('type')=='item_completed'
        and данные.get('thread_id')==исполнитель,'время получено другим исполнителем')
    элемент=данные.get('item',{})
    требовать(type(элемент) is dict and элемент.get('type')=='CommandExecution'
        and элемент.get('source')=='unified_exec_startup'
        and элемент.get('status')=='completed' and type(элемент.get('exit_code')) is int
        and элемент['exit_code']==0 and элемент.get('cwd') in (str(корень),корень.as_uri()),
        'неподтверждённый собственный CLI времени')
    команда=элемент.get('command')
    варианты=[['интерпретатор','Инструменты/fum-moskovskoye-vremya-rabochej-sessii/scripts/get-session-time.py','--format','both'],
        ['интерпретатор','-B','Инструменты/fum-moskovskoye-vremya-rabochej-sessii/scripts/get-session-time.py','--format','both']]
    прямые=[[исполняемый,*в[1:]] for в in варианты for исполняемый in ('python3','/usr/bin/python3')]
    обёртки=[['/bin/zsh','-lc',' '.join(в)] for в in прямые]
    требовать(type(команда) is list and команда in прямые+обёртки,
        'нужен прямой штатный --format both без подстановки даты')
    вывод=элемент.get('aggregated_output')
    требовать(type(вывод) is str and вывод.count('\n')==2 and '\r' not in вывод
        and вывод.endswith('\n'),'нет точного двухстрочного RAW вывода времени')
    return генератор.разобрать_время(вывод)

    требовать(вход['позднее_решение'] is None and вход['выбор_акта'] is None
        and вход['писатель']==нативный['исполнитель'] and str(корень)==вход['исполнитель']['корень']
        and вход['источник_модели']==вход['исполнитель']['источник_модели']
        and снимок['HEAD']==вход['постановка']['коммит'] and снимок['ref']==решение['акт']['ветка'],
        'начало допустимо только собственному исполнителю ровно на C/ref')
    позиция=вход['поздняя_привязка'];префикс,метка=_исходное_время(вход,позиция)
    политика=решение['поздний_журнал'];имя=префикс+'_'+политика['метка']
    команды=м.этап.корневые_команды({'корень':str(корень),'источники':вход['источники']})
    требовать([э['текст'] for э in команды]==_команды_начала(вход,решение),
        'команды начала не подтверждены первоначальными RAW B0')

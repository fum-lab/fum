def _семантика(корень,выбор):
    м=генератор(); сырые,сведения=м.источник(корень,выбор)
    решение=м.этап.коммит.сообщения._разобрать(сырые)
    м.поля(решение,{'схема','координатор','модель','усилие','постановка','поручение',
        'акт','подготовка','зависимости','координация','поздний_журнал'})
    требовать(решение['схема']=='fum.смысл-дочернего-поручения.3','.4 требует явного семантического входа .3')
    блок_политики(решение['поздний_журнал'])
    м.поля(решение['акт'],{'путь','ветка','область'});м.поля(решение['постановка'],{'путь','текст'})
    м.поля(решение['подготовка'],{'корень','исполнитель'})
    требовать(решение['зависимости']==['журнал','recency'],'неполные зависимости позднего перехода')
    м.обычное.проверить_область(корень,решение['акт']['область'],[
        п+'проверка-покрытия' if п.endswith('/') else п for п in решение['акт']['область']])
    требовать(all(not п.startswith(('Журнал/','Индексы/')) for п in решение['акт']['область']),
        'первоначальная предметная область не назначает будущую папку или служебную область')
    м.поля(решение['подготовка']['исполнитель'],{
        'заголовок','описание','роль','цели','проверки','наполнение','предел_секунд'})
    требовать(решение['подготовка']['исполнитель']['заголовок']==решение['поздний_журнал']['заголовок'],
        'подмена заголовка поздней папки')
    for ключ in ('модель','усилие'): требовать(м.автор.проверить_токен(решение[ключ]),'неизвестная модель или усилие')
    return решение,сведения


def _вход(вход):
    м=генератор()
    м.поля(вход,{'схема','фаза','корень','писатель','решение','каталог_выходов','источник_модели',
        'источники','область_писателя','постановка','исполнитель','выбор_акта','основание_координации',
        'живой_источник','поздняя_привязка','позднее_решение'})
    требовать(вход['схема']=='fum.подготовка-дочернего-поручения.4'
        and вход['фаза'] in {'постановка','начало','акт','входы'},'неизвестный переход .4')
    каталог=м.этап.адреса.точный_абсолютный(вход['каталог_выходов'],приватный=True)
    с=каталог.stat()
    требовать(stat.S_ISDIR(с.st_mode) and с.st_uid==os.getuid() and stat.S_IMODE(с.st_mode)==0o700,
        'нужен собственный каталог0700')
    требовать(type(вход['источники']) is list and len(вход['источники'])==1,
        'нужен один явно подготовленный командный снимок')
    return каталог


def _живой_вход(вход,смысл):
    частный=copy.deepcopy(вход)
    источник=частный['источники'][0]
    источник.update(путь=вход['живой_источник'],граница_снимка={
        'граница':смысл['контекст']['граница'],'sha256':смысл['контекст']['sha256'],
        'неоднозначные_экземпляры':смысл['решение']['рассмотренные_неоднозначности']})
    оригиналы=частный['основание_координации']['оригиналы']
    требовать(type(оригиналы) is list and all(type(э) is dict and set(э)=={'экземпляр','путь','sha256'} for э in оригиналы),
        'неверный объединённый набор RAW')
    по_номеру={э['экземпляр']:э for э in оригиналы}
    требовать(len(по_номеру)==len(оригиналы),'повторённый RAW в объединённом наборе')
    выбранные=set(смысл['экземпляры']+смысл['решение']['поздние'])
    требовать(выбранные<=set(по_номеру),'нет всех RAW выбранного рассмотрения')
    частный['основание_координации']['оригиналы']=[по_номеру[э] for э in смысл['контекст']['экземпляры'] if э in выбранные]
    return частный


def _командный_снимок(вход,контекст):
    """Снимок уже материализован явно; обычный preview/apply его не копирует."""
    м=генератор(); источник=вход['источники'][0]
    требовать(источник['путь']!=вход['живой_источник'],'исторический command snapshot не является LIVE')
    файл=м.этап.адреса.точный_абсолютный(источник['путь'],приватный=True)
    м.этап.коммит.сообщения._обычный(файл.stat(),приватный=True)
    требовать(stat.S_IMODE(файл.stat().st_mode)==0o400 and файл.stat().st_size==контекст['граница'],
        'нужен отдельный неизменяемый command snapshot ровно до B')
    требовать(источник['граница_снимка']['граница']==контекст['граница']
        and источник['граница_снимка']['sha256']==контекст['sha256'],'command snapshot не совпал с рассмотренным B')
    with файл.open('rb') as поток:
        до=основание.читатель._метка(os.fstat(поток.fileno()))
        независимый,_=основание.читатель._прочитать_поток(поток,источник['задача'],None,предел=контекст['граница'])
        требовать(основание.читатель._метка(os.fstat(поток.fileno()))==до
            and основание.читатель._метка(файл.stat())==до,'command snapshot изменился при чтении')
    требовать(основание.обработка.контекст_снимка(независимый)==контекст,'command snapshot подменён')
    данные=м.этап.коммит.сообщения._кэш_прочитать(Path(источник['кэш']),источник['задача'])
    требовать(данные is not None and {к:в for к,в in данные.items() if к!='метка'}
        =={к:в for к,в in независимый.items() if к!='метка'},
        'командный кэш подменил RAW, содержание или порядок рассмотренных экземпляров')


def _исходное(вход):
    м=генератор(); корень,снимок=м.собственное_дерево(вход)
    решение,сведения=_семантика(корень,вход['решение'])
    требовать(вход['источники'][0]['задача']==решение['координатор'],'чужой источник команд')
    историческое=основание.проверить_рассмотренный_префикс(корень,решение,
        _живой_вход(вход,решение['координация']))
    нативный=None
    if вход['фаза']!='постановка':
        пост,_=м.источник(корень,вход['постановка']);м.сверить_постановку(решение,вход['постановка'],пост)
        нативный=м.нативная_привязка(решение,вход['исполнитель'],вход['постановка'],историческое)
    return корень,снимок,решение,сведения,историческое,нативный


def составить_приглашение(корень,выбор_решения,выбор_постановки,вход):
    м=генератор(); требовать(type(вход) is dict and вход.get('схема')=='fum.подготовка-дочернего-поручения.4',
        'приглашение .3 требует приватного входа .4')

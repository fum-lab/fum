СХЕМА_КВИТАНЦИИ = "fum.квитанция-этапа.1"
КАТАЛОГ_КВИТАНЦИЙ = "Планирование/квитанции-конвейера"
КАТАЛОГ_НАЗНАЧЕНИЙ = "Планирование/назначения-конвейера"
_UUID = re.compile(r"[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\Z")
_ХЭШ = re.compile(r"[0-9a-f]{64}\Z")
_ЭТАП = re.compile(r"[a-z0-9]+(?:[a-z0-9-]*/)*v[1-9][0-9]*\Z")


class ОшибкаРеестра(ValueError):
    """Учёт этапа не доказан; повторный запуск запрещён."""


class ДубликатОбработки(ОшибкаРеестра):
    """Та же пара исходного события и этапа уже зарезервирована либо выполнена."""


def требовать(условие, причина):
    if not условие:
        raise ОшибкаРеестра(причина)


def канонические_байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True,
                       separators=(",", ":"), allow_nan=False) + "\n").encode("utf-8")


def байты_квитанции(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False) + "\n").encode("utf-8")


def хэш_байтов(значение):
    return hashlib.sha256(значение).hexdigest()


def хэш_значения(значение):
    return хэш_байтов(канонические_байты(значение))


def _uuid(значение):
    требовать(type(значение) is str and _UUID.fullmatch(значение) is not None,
              "Нужен канонический UUID задачи")


def _хэш(значение, название):
    требовать(type(значение) is str and _ХЭШ.fullmatch(значение) is not None,
              "Неверный SHA-256: " + название)


def проверить_событие(событие):
    требовать(type(событие) is dict and set(событие) == {"задача", "источник", "экземпляр", "позиция"},
              "Неизвестная схема исходного события")
    _uuid(событие["задача"])
    _хэш(событие["источник"], "источник")
    _хэш(событие["экземпляр"], "экземпляр")
    позиция = событие["позиция"]
    требовать(type(позиция) is dict and set(позиция) == {"начало", "конец", "sha256"},
              "Неверная позиция исходного события")
    требовать(type(позиция["начало"]) is int and type(позиция["конец"]) is int
              and 0 <= позиция["начало"] < позиция["конец"], "Неверный байтовый диапазон события")
    _хэш(позиция["sha256"], "строка события")
    ожидаемый = хэш_значения({"задача": событие["задача"], "источник": событие["источник"], **позиция})
    требовать(событие["экземпляр"] == ожидаемый,
              "ID события не соответствует задаче, источнику, позиции и хэшу строки")
    return событие


def проверить_этап(этап):
    требовать(type(этап) is str and len(этап) <= 180 and _ЭТАП.fullmatch(этап) is not None
              and all(часть not in {".", ".."} for часть in этап.split("/")),
              "Этап должен быть стабильным путём с явной версией vN")
    return этап


def путь_квитанции(событие, этап, claim_id):
    проверить_событие(событие)
    проверить_этап(этап)
    _uuid(claim_id)
    ключ_события = хэш_значения({"задача": событие["задача"], "экземпляр": событие["экземпляр"]})
    ключ_этапа = хэш_байтов(этап.encode("utf-8"))
    return f"{КАТАЛОГ_КВИТАНЦИЙ}/{ключ_этапа}/{ключ_события}-{claim_id}.json"


def путь_назначения(событие, этап, назначение_id):
    проверить_событие(событие)
    проверить_этап(этап)
    _uuid(назначение_id)
    ключ_события = хэш_значения({"задача": событие["задача"], "экземпляр": событие["экземпляр"]})
    ключ_этапа = хэш_байтов(этап.encode("utf-8"))
    return f"{КАТАЛОГ_НАЗНАЧЕНИЙ}/{ключ_этапа}/{ключ_события}-{назначение_id}.json"


def ключ_работы(событие, этап):
    проверить_событие(событие)
    проверить_этап(этап)
    return хэш_значения({"задача": событие["задача"], "экземпляр": событие["экземпляр"], "этап": этап})


def _git(корень, *аргументы, бинарный=False):
    среда = {ключ: значение for ключ, значение in os.environ.items() if not ключ.startswith("GIT_")}
    среда["GIT_OPTIONAL_LOCKS"] = "0"
    процесс = subprocess.run(["git", "--no-replace-objects", "-c", "core.quotepath=false", *аргументы],
                             cwd=корень, env=среда, capture_output=True)
    if процесс.returncode:
        raise ОшибкаРеестра("Не удалось проверить Git-состояние")
    return процесс.stdout if бинарный else процесс.stdout.decode("utf-8")


def _blob_коммита(корень, ref, путь):
    записи = _git(корень, "ls-tree", "-r", "-z", "--full-tree", ref, "--", путь, бинарный=True).split(b"\0")
    записи = [э for э in записи if э.endswith(b"\t" + путь.encode("utf-8"))]
    требовать(len(записи) == 1, "Путь не присутствует ровно один раз в требуемом коммите")
    режим, тип, oid = записи[0].split(b"\t", 1)[0].decode("ascii").split(" ")
    требовать(тип == "blob" and режим in {"100644", "100755"}, "Ожидался обычный Git-файл")
    return _git(корень, "cat-file", "blob", oid, бинарный=True)


def _путь_выхода(корень, имя):
    требовать(type(имя) is str and bool(имя), "Пустой путь результата")
    путь = PurePosixPath(имя)
    требовать(not путь.is_absolute() and путь.as_posix() == имя and ".." not in путь.parts
              and ".git" not in путь.parts
              and not any(имя.startswith(каталог + "/") for каталог in (КАТАЛОГ_КВИТАНЦИЙ, КАТАЛОГ_НАЗНАЧЕНИЙ)),
              "Небезопасный либо рекурсивный путь результата")
    физический = корень.joinpath(*путь.parts)
    текущий = корень
    for часть in путь.parts:
        текущий = текущий / часть
        требовать(not текущий.is_symlink(), "Символическая ссылка в пути результата")
    return физический


def _обычный_файл(путь):
    состояние = путь.lstat()
    требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1,
              "Результат должен быть обычным файлом без жёстких ссылок")
    return хэш_байтов(путь.read_bytes())


def _проверить_путь_контракта(имя):
    требовать(type(имя) is str and bool(имя), "Пустой путь контракта")
    путь = PurePosixPath(имя)
    требовать(not путь.is_absolute() and путь.as_posix() == имя and ".." not in путь.parts
              and ".git" not in путь.parts
              and not any(имя.startswith(каталог + "/") for каталог in (КАТАЛОГ_КВИТАНЦИЙ, КАТАЛОГ_НАЗНАЧЕНИЙ)),
              "Небезопасный либо служебный путь контракта")
    return имя


def _проверить_квитанцию(квитанция):
    поля = {"схема", "событие", "этап", "контракт", "контракт_sha256", "назначение_id", "claim_id", "исполнитель", "ref", "база", "выходы"}
    требовать(type(квитанция) is dict and set(квитанция) == поля, "Неизвестные поля квитанции этапа")
    требовать(квитанция["схема"] == СХЕМА_КВИТАНЦИИ, "Неизвестная схема квитанции этапа")
    проверить_событие(квитанция["событие"])
    проверить_этап(квитанция["этап"])
    _проверить_путь_контракта(квитанция["контракт"])
    _хэш(квитанция["контракт_sha256"], "контракт этапа")
    _uuid(квитанция["назначение_id"])
    _uuid(квитанция["claim_id"])
    _uuid(квитанция["исполнитель"])
    требовать(type(квитанция["ref"]) is str and
              (квитанция["ref"] == "refs/heads/fuma" or квитанция["ref"] == "refs/heads/planirovaniye"
               or квитанция["ref"].startswith("refs/heads/codex/")), "Недопустимая ветка исполнителя")
    требовать(type(квитанция["база"]) is str and re.fullmatch(r"[0-9a-f]{40}", квитанция["база"]) is not None,
              "Нужен полный OID исходного коммита")
    требовать(type(квитанция["выходы"]) is dict and bool(квитанция["выходы"]), "Нет хэшей результатов этапа")
    for путь, отпечаток in квитанция["выходы"].items():
        _проверить_путь_контракта(путь)
        _хэш(отпечаток, "результат")
    return квитанция


def _проверить_назначение(назначение):
    поля = {"схема", "назначение_id", "событие", "этап", "контракт", "контракт_sha256", "исполнитель", "ref", "база", "выходы"}
    требовать(type(назначение) is dict and set(назначение) == поля, "Неизвестные поля назначения этапа")
    требовать(назначение["схема"] == "fum.назначение-этапа.1", "Неизвестная схема назначения")
    _uuid(назначение["назначение_id"])
    проверить_событие(назначение["событие"])
    проверить_этап(назначение["этап"])
    _проверить_путь_контракта(назначение["контракт"])
    _хэш(назначение["контракт_sha256"], "контракт этапа")
    _uuid(назначение["исполнитель"])
    требовать(назначение["ref"] == "refs/heads/fuma", "Назначение должно быть создано в постоянной ветке fuma")
    требовать(type(назначение["база"]) is str and re.fullmatch(r"[0-9a-f]{40}", назначение["база"]) is not None,
              "Нужен полный OID основания назначения")
    требовать(type(назначение["выходы"]) is list and bool(назначение["выходы"])
              and all(type(путь) is str and bool(путь) for путь in назначение["выходы"])
              and len(set(назначение["выходы"])) == len(назначение["выходы"]),
              "Нужен непустой список уникальных результатов")
    for путь in назначение["выходы"]:
        _проверить_путь_контракта(путь)
    return назначение


def проверить_набор_квитанций(квитанции):
    """Одинаковые копии квитанции допустимы; два выполнения одной пары — нет."""
    по_работе = {}
    по_попытке = {}
    for исходная in квитанции:
        запись = _проверить_квитанцию(исходная)
        ключ = ключ_работы(запись["событие"], запись["этап"])
        тело = байты_квитанции(запись)
        старая_попытка = по_попытке.get(запись["claim_id"])
        требовать(старая_попытка is None or старая_попытка == тело,
                  "Один claim_id имеет противоречащие квитанции")
        по_попытке[запись["claim_id"]] = тело
        прежняя = по_работе.get(ключ)
        требовать(прежняя is None or прежняя["claim_id"] == запись["claim_id"],
                  "Обнаружены две выполненные работы для одного события и этапа")
        по_работе[ключ] = запись
    return list(по_работе.values())


def проверить_набор_назначений(назначения):
    по_работе = {}
    по_попытке = {}
    for исходная in назначения:
        запись = _проверить_назначение(исходная)
        ключ = ключ_работы(запись["событие"], запись["этап"])
        тело = байты_квитанции(запись)
        прежняя_попытка = по_попытке.get(запись["назначение_id"])
        требовать(прежняя_попытка is None or прежняя_попытка == тело,
                  "Один ID назначения имеет противоречащие записи")
        по_попытке[запись["назначение_id"]] = тело
        прежняя = по_работе.get(ключ)
        требовать(прежняя is None or прежняя["назначение_id"] == запись["назначение_id"],
                  "Обнаружены два параллельных назначения одного события и этапа")
        по_работе[ключ] = запись
    return list(по_работе.values())


def _проверить_файловую_систему(путь, *, каталог=False):
    требовать(not путь.is_symlink(), "Символическая ссылка в приватном реестре")
    if путь.exists():
        состояние = путь.stat()
        требовать((stat.S_ISDIR(состояние.st_mode) if каталог else stat.S_ISREG(состояние.st_mode))
                  and состояние.st_uid == os.getuid(), "Реестр принадлежит другому владельцу или имеет неверный тип")
        if not каталог:
            требовать(состояние.st_nlink == 1 and состояние.st_mode & 0o077 == 0,
                      "Файл реестра не является приватным обычным файлом")


def _квитанции_ветки(корень, ref):
    требовать(type(ref) is str and (ref == "HEAD" or ref.startswith("refs/heads/") or ref.startswith("refs/remotes/")),
              "Нужен полный Git ref")
    вывод = _git(корень, "ls-tree", "-r", "-z", "--full-tree", ref, "--", КАТАЛОГ_КВИТАНЦИЙ, бинарный=True)
    квитанции = []
    for элемент in вывод.split(b"\0"):
        if not элемент:
            continue
        метаданные, путь_байты = элемент.split(b"\t", 1)
        режим, тип, oid = метаданные.decode("ascii").split(" ")
        путь = путь_байты.decode("utf-8")
        требовать(тип == "blob" and режим == "100644" and путь.endswith(".json"),
                  "Недопустимый тип файла в каталоге квитанций")
        сырые = _git(корень, "cat-file", "blob", oid, бинарный=True)
        запись = json.loads(сырые.decode("utf-8"))
        требовать(байты_квитанции(запись) == сырые, "Квитанция не в каноническом JSON")
        _проверить_квитанцию(запись)
        требовать(путь == путь_квитанции(запись["событие"], запись["этап"], запись["claim_id"]),
                  "Путь квитанции не соответствует событию, этапу и попытке")
        байты_контракта = _blob_коммита(корень, ref, запись["контракт"])
        требовать(хэш_байтов(байты_контракта) == запись["контракт_sha256"],
                  "Контракт квитанции отсутствует или изменён в Git-коммите")
        for выход, ожидаемый in запись["выходы"].items():
            совпадения = _git(корень, "ls-tree", "-r", "-z", "--full-tree", ref, "--", выход, бинарный=True).split(b"\0")
            найдено = [элемент for элемент in совпадения if элемент.endswith(b"\t" + выход.encode("utf-8"))]
            требовать(len(найдено) == 1, "Результат квитанции отсутствует либо неоднозначен в коммите")
            режим_выхода, тип_выхода, oid_выхода = найдено[0].split(b"\t", 1)[0].decode("ascii").split(" ")
            требовать(тип_выхода == "blob" and режим_выхода in {"100644", "100755"}
                      and хэш_байтов(_git(корень, "cat-file", "blob", oid_выхода, бинарный=True)) == ожидаемый,
                      "Содержимое результата не совпадает с квитанцией")
        квитанции.append(запись)
    return квитанции


def _назначения_ветки(корень, ref):
    требовать(type(ref) is str and (ref == "HEAD" or ref.startswith("refs/heads/") or ref.startswith("refs/remotes/")),
              "Нужен полный Git ref")
    вывод = _git(корень, "ls-tree", "-r", "-z", "--full-tree", ref, "--", КАТАЛОГ_НАЗНАЧЕНИЙ, бинарный=True)
    назначения = []
    for элемент in вывод.split(b"\0"):
        if not элемент:
            continue
        метаданные, путь_байты = элемент.split(b"\t", 1)
        режим, тип, oid = метаданные.decode("ascii").split(" ")
        путь = путь_байты.decode("utf-8")
        требовать(тип == "blob" and режим == "100644" and путь.endswith(".json"),
                  "Недопустимый тип файла в каталоге назначений")
        сырые = _git(корень, "cat-file", "blob", oid, бинарный=True)
        запись = json.loads(сырые.decode("utf-8"))
        требовать(байты_квитанции(запись) == сырые, "Назначение не в каноническом JSON")
        _проверить_назначение(запись)
        требовать(путь == путь_назначения(запись["событие"], запись["этап"], запись["назначение_id"]),
                  "Путь назначения не соответствует событию, этапу и ID")
        байты_контракта = _blob_коммита(корень, ref, запись["контракт"])
        требовать(хэш_байтов(байты_контракта) == запись["контракт_sha256"],
                  "Контракт назначения отсутствует или изменён в Git-коммите")
        назначения.append(запись)
    return назначения


def проверить_ветки(корень, refs=None):
    вершина = Path(корень).resolve(strict=True)
    refs = refs or _git(вершина, "for-each-ref", "--format=%(refname)", "refs/heads/", "refs/remotes/").splitlines()
    назначения, квитанции = [], []
    for ref in sorted(set(refs)):
        назначения.extend(_назначения_ветки(вершина, ref))
        квитанции.extend(_квитанции_ветки(вершина, ref))
    назначения = проверить_набор_назначений(назначения)
    квитанции = проверить_набор_квитанций(квитанции)
    по_назначениям = {ключ_работы(з["событие"], з["этап"]): з for з in назначения}
    for квитанция in квитанции:
        ключ = ключ_работы(квитанция["событие"], квитанция["этап"])
        назначение = по_назначениям.get(ключ)
        требовать(назначение is not None and назначение["назначение_id"] == квитанция["назначение_id"],
                  "Квитанция не связана с единственным назначением из fuma")
        требовать(назначение["исполнитель"] == квитанция["исполнитель"]
                  and назначение["контракт"] == квитанция["контракт"]
                  and назначение["контракт_sha256"] == квитанция["контракт_sha256"]
                  and назначение["выходы"] == sorted(квитанция["выходы"]),
                  "Квитанция изменила назначенного исполнителя, контракт или набор результатов")
    return {"назначения": назначения, "квитанции": квитанции}


def _текущая_позиция(корень):
    ref = _git(корень, "symbolic-ref", "-q", "HEAD").strip()
    требовать(ref == "refs/heads/fuma" or ref == "refs/heads/planirovaniye" or ref.startswith("refs/heads/codex/"),
              "Исполнение этапа допускается только в разрешённой именованной ветке")
    oid = _git(корень, "rev-parse", "HEAD").strip()
    требовать(re.fullmatch(r"[0-9a-f]{40}", oid) is not None, "Нужен полный HEAD")
    return ref, oid


class Реестр:
    """Общий для linked worktrees SQLite-допуск в Git common-dir."""

    def __init__(self, корень):
        путь = Path(корень).resolve(strict=True)
        требовать(Path(_git(путь, "rev-parse", "--show-toplevel").strip()).resolve() == путь,
                  "Нужен физический корень checkout")
        self.корень = путь
        self.общий = Path(_git(путь, "rev-parse", "--path-format=absolute", "--git-common-dir").strip()).resolve(strict=True)
        требовать(self.общий.is_dir() and self.общий.stat().st_uid == os.getuid(), "Недоступная общая Git-база")
        self.каталог = self.общий / "fum-реестр-этапов-v1"
        self.база = self.каталог / "состояние.sqlite3"

    @contextmanager
    def _транзакция(self, создать=False):
        _проверить_файловую_систему(self.каталог, каталог=True)
        if создать:
            self.каталог.mkdir(mode=0o700, exist_ok=True)
            _проверить_файловую_систему(self.каталог, каталог=True)
            требовать(self.каталог.stat().st_mode & 0o077 == 0,
                      "Общий каталог реестра должен оставаться приватным")
        требовать(self.каталог.is_dir(), "Общий реестр этапов ещё не создан")
        _проверить_файловую_систему(self.база)
        существовала = self.база.exists()
        if создать and not существовала:
            дескриптор = os.open(self.база, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, 0o600)
            os.close(дескриптор)
        соединение = sqlite3.connect(self.база, timeout=10.0, isolation_level=None)
        try:
            os.chmod(self.база, 0o600)
            _проверить_файловую_систему(self.база)
            соединение.execute("PRAGMA synchronous=FULL")
            соединение.execute("PRAGMA foreign_keys=ON")
            версия = соединение.execute("PRAGMA user_version").fetchone()[0]
            if версия == 0:
                таблицы = соединение.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").fetchall()
                требовать(создать and not таблицы,
                          "Реестр не инициализирован или повреждён; повторная инициализация запрещена")
                соединение.execute("BEGIN IMMEDIATE")
                соединение.execute("CREATE TABLE IF NOT EXISTS claims (key TEXT PRIMARY KEY, event_json BLOB NOT NULL, stage TEXT NOT NULL, contract TEXT NOT NULL, contract_path TEXT NOT NULL, owner TEXT NOT NULL, outputs_json BLOB NOT NULL, assignment_id TEXT NOT NULL UNIQUE, assignment_path TEXT NOT NULL, assignment_json BLOB NOT NULL, state TEXT NOT NULL, checkout TEXT, ref TEXT, base TEXT, claim_id TEXT UNIQUE, receipt_path TEXT, receipt_json BLOB, result_commit TEXT)")
                соединение.execute("PRAGMA user_version=1")
            else:
                требовать(версия == 1, "Неизвестная версия общего реестра; автоматическая переинициализация запрещена")
                соединение.execute("BEGIN IMMEDIATE")
            yield соединение
            соединение.commit()
        except BaseException:
            соединение.rollback()
            raise
        finally:
            соединение.close()

    def назначить(self, *, событие, этап, контракт, исполнитель, выходы):
        проверить_событие(событие)
        проверить_этап(этап)
        _проверить_путь_контракта(контракт)
        байты_контракта = _blob_коммита(self.корень, "HEAD", контракт)
        контракт_sha256 = хэш_байтов(байты_контракта)
        _uuid(исполнитель)
        требовать(type(выходы) is list and bool(выходы) and len(set(выходы)) == len(выходы),
                  "Нужен непустой список уникальных путей результатов")
        for путь in выходы:
            _путь_выхода(self.корень, путь)
        ref, база = _текущая_позиция(self.корень)
        требовать(ref == "refs/heads/fuma",
                  "Назначение параллельной работы создаётся только в постоянной ветке fuma")
        снимок = проверить_ветки(self.корень)
        найденные = [з for з in снимок["назначения"] + снимок["квитанции"]
                     if ключ_работы(з["событие"], з["этап"]) == ключ_работы(событие, этап)]
        if найденные:
            raise ДубликатОбработки("Этап уже назначен или выполнен в доступной Git-ветке")
        ключ = ключ_работы(событие, этап)
        отсортированные_выходы = sorted(выходы)
        with self._транзакция(создать=True) as база_данных:
            старая = база_данных.execute(
                "SELECT event_json, stage, contract, contract_path, owner, outputs_json, assignment_id, assignment_path, assignment_json, state "
                "FROM claims WHERE key=?", (ключ,)).fetchone()
            if старая:
                (старое_событие, старый_этап, старый_контракт, старый_путь_контракта, старый_владелец, старые_выходы,
                 назначение_id, путь_назначения_, сырые, состояние) = старая
                требовать(json.loads(старое_событие) == событие and старый_этап == этап,
                          "Коллизия ключа этапа")
                требовать(старый_контракт == контракт_sha256 and старый_путь_контракта == контракт
                          and старый_владелец == исполнитель
                          and json.loads(старые_выходы) == отсортированные_выходы,
                          "Этап уже занят; для изменения контракта нужна новая версия vN")
                требовать(состояние in {"создание-назначения", "назначено"},
                          "Назначение уже существует в общем локальном реестре: " + состояние)
                данные = json.loads(сырые.decode("utf-8"))
                _проверить_назначение(данные)
            else:
                назначение_id = str(uuid.uuid4())
                путь_назначения_ = путь_назначения(событие, этап, назначение_id)
                данные = {"схема": "fum.назначение-этапа.1", "назначение_id": назначение_id,
                          "событие": событие, "этап": этап, "контракт": контракт,
                          "контракт_sha256": контракт_sha256,
                          "исполнитель": исполнитель, "ref": ref, "база": база,
                          "выходы": отсортированные_выходы}
                _проверить_назначение(данные)
                сырые = байты_квитанции(данные)
                база_данных.execute(
                    "INSERT INTO claims (key,event_json,stage,contract,contract_path,owner,outputs_json,assignment_id,assignment_path,assignment_json,state) "
                    "VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                    (ключ, канонические_байты(событие), этап, контракт_sha256, контракт, исполнитель,
                     канонические_байты(отсортированные_выходы), назначение_id, путь_назначения_,
                     сырые, "создание-назначения"))
        # SQLite durably reserves the exact ID before writing the portable file. If interrupted,
        # the next call resumes these bytes and cannot create a second assignment.
        записать_атомарно(self.корень, путь_назначения_, сырые)
        with self._транзакция() as база_данных:
            состояние = база_данных.execute(
                "SELECT assignment_json, state FROM claims WHERE key=?", (ключ,)).fetchone()
            требовать(состояние is not None and состояние[0] == сырые
                      and состояние[1] in {"создание-назначения", "назначено"},
                      "Локальный допуск назначения изменился во время записи")
            if состояние[1] == "создание-назначения":
                база_данных.execute("UPDATE claims SET state='назначено' WHERE key=?", (ключ,))
        return {"решение": "назначено-в-fuma", "запускать_работу": False,
                "назначение_id": назначение_id, "путь": путь_назначения_, "состояние": "назначено",
                "пояснение": "Сначала включите назначение в коммит fuma; только потом создавайте рабочую ветку."}

    def взять(self, *, путь_назначения_, исполнитель):
        _uuid(исполнитель)
        ref, база = _текущая_позиция(self.корень)
        требовать(ref.startswith("refs/heads/codex/"),
                  "Содержательная работа выполняется в выделенной ветке, не в fuma")
        требовать(type(путь_назначения_) is str and путь_назначения_.startswith(КАТАЛОГ_НАЗНАЧЕНИЙ + "/"),
                  "Нужен путь назначения из постоянной ветки fuma")
        сырые = _blob_коммита(self.корень, "HEAD", путь_назначения_)
        данные = json.loads(сырые.decode("utf-8"))
        требовать(байты_квитанции(данные) == сырые, "Назначение в рабочем коммите изменено")
        назначение = _проверить_назначение(данные)
        контрактные_байты = _blob_коммита(self.корень, "HEAD", назначение["контракт"])
        требовать(хэш_байтов(контрактные_байты) == назначение["контракт_sha256"],
                  "Рабочая ветка не содержит точный назначенный контракт")
        требовать(назначение["исполнитель"] == исполнитель,
                  "Эта работа назначена другой задаче Codex")
        снимок = проверить_ветки(self.корень)
        ключ = ключ_работы(назначение["событие"], назначение["этап"])
        найденное = [з for з in снимок["назначения"] if ключ_работы(з["событие"], з["этап"]) == ключ]
        требовать(len(найденное) == 1 and найденное[0] == назначение,
                  "Назначение не опубликовано ровно один раз в доступных ветках")
        if any(ключ_работы(к["событие"], к["этап"]) == ключ for к in снимок["квитанции"]):
            raise ДубликатОбработки("Этап уже выполнен; повторный запуск запрещён")
        assignment_id = назначение["назначение_id"]
        with self._транзакция(создать=True) as база_данных:
            старая = база_данных.execute("SELECT event_json, stage, contract, contract_path, owner, outputs_json, assignment_id, assignment_path, assignment_json, state, checkout, ref, claim_id FROM claims WHERE key=?", (ключ,)).fetchone()
            if старая is None:
                база_данных.execute("INSERT INTO claims (key,event_json,stage,contract,contract_path,owner,outputs_json,assignment_id,assignment_path,assignment_json,state) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                    (ключ, канонические_байты(назначение["событие"]), назначение["этап"],
                     назначение["контракт_sha256"], назначение["контракт"], исполнитель,
                     канонические_байты(назначение["выходы"]),
                     assignment_id, путь_назначения_, сырые, "назначено"))
                старая = база_данных.execute("SELECT event_json, stage, contract, contract_path, owner, outputs_json, assignment_id, assignment_path, assignment_json, state, checkout, ref, claim_id FROM claims WHERE key=?", (ключ,)).fetchone()
            событие_json, этап, контракт, путь_контракта, владелец, выходы_json, старое_назначение, старый_путь, старое_json, состояние, старый_checkout, старый_ref, claim_id = старая
            требовать(json.loads(событие_json) == назначение["событие"] and этап == назначение["этап"]
                      and контракт == назначение["контракт_sha256"] and путь_контракта == назначение["контракт"]
                      and владелец == исполнитель
                      and json.loads(выходы_json) == назначение["выходы"]
                      and старое_назначение == assignment_id and старый_путь == путь_назначения_
                      and старое_json == сырые, "Локальный реестр противоречит коммиту fuma")
            if состояние == "завершён":
                raise ДубликатОбработки("Этап уже завершён в общем локальном реестре")
            if состояние in {"выполняется", "подготовлен"}:
                if старый_checkout != str(self.корень) or старый_ref != ref:
                    raise ДубликатОбработки("Этап уже выполняется в другом worktree или ветке")
                return {"решение": "возобновить-запись", "запускать_повторно": False,
                        "назначение_id": assignment_id, "claim_id": claim_id, "состояние": состояние}
            требовать(состояние == "назначено", "Назначение имеет неизвестное состояние")
            claim_id = str(uuid.uuid4())
            база_данных.execute("UPDATE claims SET state='выполняется',checkout=?,ref=?,base=?,claim_id=? WHERE key=?",
                                (str(self.корень), ref, база, claim_id, ключ))
            return {"решение": "разрешено", "запускать_повторно": True,
                    "назначение_id": assignment_id, "claim_id": claim_id, "состояние": "выполняется"}

    def подготовить_квитанцию(self, claim_id):
        _uuid(claim_id)
        with self._транзакция() as база_данных:
            строка = база_данных.execute("SELECT key, event_json, stage, contract, contract_path, owner, assignment_id, ref, base, outputs_json, state, receipt_path, receipt_json FROM claims WHERE claim_id=?", (claim_id,)).fetchone()
            требовать(строка is not None, "Неизвестный claim_id")
            ключ, сырое_событие, этап, контракт_sha256, контракт, исполнитель, assignment_id, ref, база, сырые_выходы, состояние, старый_путь, старый_json = строка
            событие = json.loads(сырое_событие)
            выходы = {}
            for путь in json.loads(сырые_выходы):
                файл = _путь_выхода(self.корень, путь)
                требовать(файл.is_file(), "Заявленный результат этапа отсутствует")
                выходы[путь] = _обычный_файл(файл)
            квитанция = {"схема": СХЕМА_КВИТАНЦИИ, "событие": событие, "этап": этап,
                         "контракт": контракт, "контракт_sha256": контракт_sha256,
                         "назначение_id": assignment_id,
                         "claim_id": claim_id, "исполнитель": исполнитель,
                         "ref": ref, "база": база, "выходы": выходы}
            _проверить_квитанцию(квитанция)
            путь = путь_квитанции(событие, этап, claim_id)
            сырые = байты_квитанции(квитанция)
            if состояние == "подготовлен":
                требовать(старый_путь == путь and старый_json == сырые,
                          "Подготовленная квитанция или результаты изменились")
                return {"путь": путь, "sha256": хэш_байтов(сырые), "состояние": состояние}
            требовать(состояние == "выполняется", "Квитанция уже имеет терминальное состояние")
            записать_атомарно(self.корень, путь, сырые)
            база_данных.execute("UPDATE claims SET state='подготовлен', receipt_path=?, receipt_json=? WHERE key=?",
                                (путь, сырые, ключ))
            return {"путь": путь, "sha256": хэш_байтов(сырые), "состояние": "подготовлен"}

    def завершить(self, claim_id):
        _uuid(claim_id)
        head = _git(self.корень, "rev-parse", "HEAD").strip()
        with self._транзакция() as база_данных:
            строка = база_данных.execute("SELECT key, state, receipt_path, receipt_json, result_commit FROM claims WHERE claim_id=?", (claim_id,)).fetchone()
            требовать(строка is not None, "Неизвестный claim_id")
            ключ, состояние, путь, сырые, прежний_commit = строка
            if состояние == "завершён":
                return {"состояние": состояние, "коммит": прежний_commit}
            требовать(состояние == "подготовлен" and путь and сырые,
                      "Сначала подготовьте результаты и квитанцию")
            дерево_квитанций = _git(self.корень, "ls-tree", "-r", "-z", "--full-tree", head, "--", путь, бинарный=True).split(b"\0")
            дерево_квитанций = [э for э in дерево_квитанций if э]
            требовать(len(дерево_квитанций) == 1, "Квитанция ещё не включена в текущий коммит")
            _, тип, oid = дерево_квитанций[0].split(b"\t", 1)[0].decode("ascii").split(" ")
            требовать(тип == "blob" and _git(self.корень, "cat-file", "blob", oid, бинарный=True) == сырые,
                      "Квитанция в коммите отличается от подготовленной")
            # Валидатор также убеждается, что каждый объявленный результат присутствует в том же дереве Git.
            снимок = проверить_ветки(self.корень)
            совпадения = [к for к in снимок["квитанции"] if к["claim_id"] == claim_id]
            требовать(len(совпадения) == 1, "Коммит не доказывает единственность и целостность результата")
            база_данных.execute("UPDATE claims SET state='завершён', result_commit=? WHERE key=?", (head, ключ))
            return {"состояние": "завершён", "коммит": head}


def записать_атомарно(корень, имя, данные):
    путь = корень.joinpath(*PurePosixPath(имя).parts)
    текущий = корень
    for часть in PurePosixPath(имя).parts[:-1]:
        текущий = текущий / часть
        требовать(not текущий.is_symlink(), "Символическая ссылка в пути квитанции")
        текущий.mkdir(mode=0o755, exist_ok=True)
        требовать(текущий.is_dir() and not текущий.is_symlink(), "Неверный тип каталога квитанции")
    требовать(not путь.is_symlink(), "Символическая ссылка вместо квитанции")
    временный = None
    try:
        with tempfile.NamedTemporaryFile(dir=путь.parent, prefix=".квитанция-", delete=False) as поток:
            временный = Path(поток.name)
            поток.write(данные)
            поток.flush()
            os.fsync(поток.fileno())
        if путь.exists():
            требовать(путь.is_file() and путь.stat().st_nlink == 1 and путь.read_bytes() == данные,
                      "Квитанция для этой попытки уже существует с другим содержимым")
            return
        os.replace(временный, путь)
        каталог = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(каталог)
        finally:
            os.close(каталог)
    finally:
        if временный is not None:
            временный.unlink(missing_ok=True)

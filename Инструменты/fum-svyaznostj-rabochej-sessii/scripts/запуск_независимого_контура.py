ПРЕФИКС = 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/'
ПУСК = ПРЕФИКС + 'запуск_независимого_контура.py'
КОНСТРУКТОР = ПРЕФИКС + 'конечный_состав_независимого_контура.py'
ДОПУСК = ПРЕФИКС + 'допуск_независимого_контура.py'
ДВИЖОК = ПРЕФИКС + 'исполнение_принятого_кода.py'
ПРЕЖНИЙ_ДОПУСК = ПРЕФИКС + 'запуск_принятого_создателя.py'
НАЧАЛЬНЫЕ_ИСХОДНИКИ = {ПУСК, КОНСТРУКТОР, ДОПУСК, ДВИЖОК, ПРЕЖНИЙ_ДОПУСК}


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def хэш(сырые):
    return hashlib.sha256(сырые).hexdigest()


def метка_файла(с):
    return (с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink, с.st_size, с.st_mtime_ns, с.st_ctime_ns)


def прочитать_начальный_файл(путь, режим=None):
    требовать(путь.is_absolute() and путь.resolve() == путь, 'нефизический начальный файл')
    до = путь.lstat()
    требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1
        and (режим is None or stat.S_IMODE(до.st_mode) == режим), 'неверные свойства начального файла')
    д = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(д, 'rb') as поток:
        требовать(метка_файла(до) == метка_файла(os.fstat(д)), 'начальный файл подменён при открытии')
        сырые = поток.read()
        требовать(метка_файла(до) == метка_файла(os.fstat(д)), 'начальный файл изменился при чтении')
    требовать(метка_файла(до) == метка_файла(путь.lstat()), 'начальный файл заменён при чтении')
    return метка_файла(до), сырые


def сверить_начальные(снимки):
    for путь, снимок in снимки.items():
        текущий = прочитать_начальный_файл(путь) if os.path.lexists(путь) else None
        требовать(текущий == снимок, 'изменилась начальная роль: ' + str(путь))


def разобрать_начальный(сырые):
    def объект(пары):
        итог = {}
        for ключ, значение in пары:
            требовать(ключ not in итог, 'повторный ключ начального JSON')
            итог[ключ] = значение
        return итог
    def отказ(значение):
        raise ValueError('нецелое число начального JSON: ' + значение)
    return json.loads(сырые, object_pairs_hook=объект, parse_float=отказ, parse_constant=отказ)


def прочитать_личный(значение, режим, *, снимки=None):
    путь = Path(значение)
    требовать(путь.is_absolute() and путь.resolve() == путь
        and not any(os.path.lexists(п / '.git') for п in путь.parents), 'нужна физическая приватная роль вне Git')
    снимок = прочитать_начальный_файл(путь, режим)
    требовать(снимок[0][3] == os.getuid(), 'чужой владелец приватной роли')
    if снимки is not None: снимки[путь] = снимок
    return снимок[1]


class КонечныеКоманды:
    """Точные логические argv; физический K-worker выбирается отдельно."""
    def __init__(сам, код, данные, команды):
        сам.код, сам.данные = Path(код), Path(данные)
        требовать(not (сам.код.is_relative_to(сам.данные) or сам.данные.is_relative_to(сам.код)),
            'физические K/W должны быть раздельными')
        требовать(type(команды) is list and команды, 'нужны выбранные дочерние CLI')
        сам.команды = команды
        for команда in команды:
            требовать(type(команда) is dict and set(команда) == {'путь', 'аргументы'}
                and type(команда['путь']) is str and type(команда['аргументы']) is list
                and all(type(а) is str for а in команда['аргументы']), 'неверная конечная команда')
            путь = PurePosixPath(команда['путь'])
            требовать(not путь.is_absolute() and путь.as_posix() == команда['путь']
                and all(ч not in {'.', '..', '.git'} for ч in путь.parts), 'неверный путь CLI')
            требовать(not {'-c', '-m'}.intersection(команда['аргументы']),
                'невыбранная форма Python CLI; свободное discovery запрещено')
        for команда in команды:
            аргументы = команда['аргументы']
            if аргументы and аргументы[0] == 'запустить':
                требовать('--' in аргументы, 'нет выбранного вложенного хвоста RAW')
                сам.распознать(аргументы[аргументы.index('--') + 1:])

    def разделить(сам, аргументы):
        требовать(type(аргументы) in (list, tuple) and len(аргументы) >= 2
            and all(type(а) is str for а in аргументы), 'нужен точный argv дочернего CLI')
        требовать(Path(аргументы[0]).is_absolute()
            and Path(аргументы[0]).resolve() == Path(sys.executable).resolve(), 'чужой Python CLI')
        номер = 1
        while номер < len(аргументы) and аргументы[номер] in {'-I', '-S', '-B', '-E'}:
            номер += 1
        требовать(номер < len(аргументы) and not аргументы[номер].startswith('-'),
            'невыбранная форма Python CLI')
        путь = Path(аргументы[номер])
        if not путь.is_absolute():
            путь = сам.данные / путь
        относительный = None
        for корень in (сам.код, сам.данные):
            if путь.is_relative_to(корень):
                относительный = путь.relative_to(корень).as_posix()
                break
        требовать(относительный is not None and '..' not in Path(относительный).parts,
            'дочерний CLI вне выбранных K/W')
        return относительный, list(аргументы[номер + 1:])

    @staticmethod
    def совпадает(шаблон, фактический):
        if len(шаблон) != len(фактический):
            return False
        for ожидаемый, реальный in zip(шаблон, фактический):
            if ожидаемый.startswith('@sha256:'):
                путь = Path(ожидаемый.removeprefix('@sha256:'))
                if not путь.is_absolute() or путь.resolve() != путь or not путь.is_file():
                    return False
                if re.fullmatch('[0-9a-f]{64}', реальный) is None or хэш(путь.read_bytes()) != реальный:
                    return False
            elif ожидаемый != реальный:
                return False
        return True

    def распознать(сам, аргументы):
        путь, хвост = сам.разделить(аргументы)
        требовать(any(к['путь'] == путь and сам.совпадает(к['аргументы'], хвост)
            for к in сам.команды), 'дочерний CLI/argv не выбран заранее: ' + путь)
        return путь, хвост


def безопасный_гит(корень, *аргументы, вход=None):
    части = os.environ.get('PATH', '').split(os.pathsep)
    требовать(части and all(п and Path(п).is_absolute() for п in части), 'нужен абсолютный PATH до Git')
    найденный = shutil.which('git')
    требовать(найденный is not None, 'Git не найден')
    исполняемый = Path(найденный).resolve()
    требовать(not any(исполняемый.is_relative_to(п) for п in (Path(корень), Path.cwd())),
        'Git не может исполняться из K или W')
    среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_NO_LAZY_FETCH='1', GIT_NO_REPLACE_OBJECTS='1', GIT_TERMINAL_PROMPT='0',
        GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull, GIT_OPTIONAL_LOCKS='0')
    return subprocess.check_output([str(исполняемый), '--no-optional-locks', '--no-replace-objects',
        '-c', 'core.hooksPath=' + os.devnull, '-c', 'core.fsmonitor=false',
        '-c', 'protocol.allow=never', '-C', str(корень), *аргументы], input=вход, env=среда)


def проверить_начальное_хранилище(корень):
    отметка = корень / '.git'
    снимки = {}
    if отметка.is_dir() and not отметка.is_symlink():
        служебный = отметка
    else:
        снимки[отметка] = прочитать_начальный_файл(отметка)
        строка = снимки[отметка][1].decode().strip()
        требовать(строка.startswith('gitdir: ') and '\n' not in строка, 'неверный gitdir K')
        служебный = Path(os.path.abspath(корень / строка[8:]))
    требовать(служебный.resolve() == служебный, 'нефизический gitdir K')
    общий = служебный
    связь = служебный / 'commondir'
    if os.path.lexists(связь):
        снимки[связь] = прочитать_начальный_файл(связь)
        общий = Path(os.path.abspath(служебный / снимки[связь][1].decode().strip()))
    требовать(общий.resolve() == общий and not os.path.lexists(общий / 'shallow'),
        'неполное или нефизическое хранилище K')
    снимки[общий / 'shallow'] = None
    for конфиг in (общий / 'config', служебный / 'config.worktree'):
        снимки[конфиг] = прочитать_начальный_файл(конфиг) if os.path.lexists(конфиг) else None
        if снимки[конфиг] is None: continue
        поля = безопасный_гит(корень, 'config', '--file', str(конфиг), '--no-includes', '--null', '--list')
        for поле in поля.split(b'\0'):
            ключ = поле.split(b'\n', 1)[0].decode().lower()
            требовать(not (ключ.startswith('include') or ключ == 'extensions.partialclone'
                or ключ.startswith('remote.') and ключ.endswith(('.promisor', '.partialclonefilter'))),
                'неполная или include-конфигурация K запрещена до compile')
    сверить_начальные(снимки)
    return снимки


def начальный_blob(корень, коммит, путь, ожидаемый, *, снимки=None):
    требовать(re.fullmatch('[0-9a-f]{40}', коммит) is not None
        and re.fullmatch('[0-9a-f]{64}', ожидаемый) is not None, 'неверный начальный pin')
    запись = безопасный_гит(корень, 'ls-tree', '-z', коммит, '--', путь).split(b'\0')
    требовать(len(запись) == 2 and not запись[-1], 'нет точного начального blob')
    мета, имя = запись[0].split(b'\t'); режим, тип, объект = мета.decode().split()
    требовать(имя.decode() == путь and режим == '100644' and тип == 'blob', 'необычный начальный blob')
    сырые = безопасный_гит(корень, 'cat-file', 'blob', объект)
    снимок = прочитать_начальный_файл(корень / путь, 0o644)
    требовать(hashlib.sha1(b'blob ' + str(len(сырые)).encode() + b'\0' + сырые).hexdigest() == объект
        and хэш(сырые) == ожидаемый and снимок[1] == сырые,
        'начальный исходник не равен выбранным Git-байтам')
    if снимки is not None: снимки[корень / путь] = снимок
    return сырые


def загрузить_начальный(имя, путь, сырые, *, снимки=None):
    # Bootstrap-роль закреплена извне; в sys.modules проектный код не помещается.
    if снимки is not None: сверить_начальные(снимки)
    модуль = types.ModuleType(имя); модуль.__file__ = str(путь)
    exec(compile(сырые, str(путь), 'exec', dont_inherit=True), модуль.__dict__)
    return модуль


def запустить(п):
    требовать(sys.flags.isolated and sys.flags.no_site and sys.dont_write_bytecode,
        'нужен свежий процесс -I -S -B')
    файл = Path(п.манифест)
    начальные_снимки = {}
    сырые = прочитать_личный(файл, 0o600, снимки=начальные_снимки)
    требовать(хэш(сырые) == п.sha256, 'подменён выбранный манифест')
    настройки = разобрать_начальный(сырые)
    требовать(type(настройки) is dict and настройки.get('схема') == 'fum.запуск-независимого-контура.1',
        'неизвестная схема манифеста')
    данные = Path(настройки['данные']['корень'])
    требовать(данные.is_absolute() and данные.resolve() == данные and Path.cwd() == данные,
        'нужен выбранный физический cwd W до запуска Git')
    корень = Path(настройки['код']['корень']); коммит = настройки['код']['коммит']
    требовать(корень.is_absolute() and корень.resolve() == корень and Path(__file__) == корень / ПУСК,
        'нужен собственный физический bootstrap выбранного K')
    начальные_снимки.update(проверить_начальное_хранилище(корень))
    требовать(безопасный_гит(корень, 'rev-parse', '--show-toplevel').decode().strip() == str(корень),
        'K должен быть настоящим Git-корнем')
    начальные = настройки['начальные_исходники']
    требовать(type(начальные) is dict and set(начальные) == НАЧАЛЬНЫЕ_ИСХОДНИКИ,
        'неполный закрытый начальный состав')
    исходники = {путь: начальный_blob(корень, коммит, путь, начальные[путь],
        снимки=начальные_снимки) for путь in sorted(начальные)}
    сверить_начальные(начальные_снимки)
    конструктор = загрузить_начальный('начальный_конструктор', корень / КОНСТРУКТОР,
        исходники[КОНСТРУКТОР], снимки=начальные_снимки)
    настройки = конструктор.разобрать(сырые)
    выбор = настройки['конечный_выбор']
    требовать(bool(п.одобрение_профиля) == bool(п.sha256_одобрения), 'неполное внешнее одобрение')
    внешние = {}; одобрение = None
    if п.одобрение_профиля:
        профиль = прочитать_личный(выбор['путь'], 0o400, снимки=начальные_снимки)
        сырые_одобрения = прочитать_личный(п.одобрение_профиля, 0o400, снимки=начальные_снимки)
        одобрение = конструктор.проверить_одобрение(сырые_одобрения, п.sha256_одобрения, профиль,
            коммит=коммит, дерево=безопасный_гит(корень, 'rev-parse', коммит + '^{tree}').decode().strip(),
            генератор=начальные[КОНСТРУКТОР])
        требовать(выбор['sha256'] == одобрение['профиль_sha256'], 'манифест не совпадает с внешним одобрением')
        внешние = {Path(выбор['путь']): профиль, Path(п.одобрение_профиля): сырые_одобрения}
    else:
        записи = конструктор.прочитать_набор(корень, коммит, [*начальные, выбор['путь']])
        требовать(записи[выбор['путь']][0]['sha256'] == выбор['sha256'], 'подменён конечный реестр K')
        профиль = записи[выбор['путь']][1]
    отпечаток = None if одобрение is None else одобрение['профиль_sha256']
    конечный = конструктор.проверенный_профиль(профиль, независимый_sha256=отпечаток)['выбор']
    конечный['команды'] = настройки['команды']
    состав = конструктор.построить(корень, коммит, конечный, профиль=профиль, независимый_sha256=отпечаток)
    сверить_начальные(начальные_снимки)
    допуск = загрузить_начальный('начальный_допуск', корень / ДОПУСК, исходники[ДОПУСК], снимки=начальные_снимки)
    движок = загрузить_начальный('начальный_движок', корень / ДВИЖОК, исходники[ДВИЖОК], снимки=начальные_снимки)
    прежний = загрузить_начальный('начальный_допуск_зависимостей', корень / ПРЕЖНИЙ_ДОПУСК,
        исходники[ПРЕЖНИЙ_ДОПУСК], снимки=начальные_снимки)
    контекст = допуск.ПроверенныйКонтур(настройки, п, состав, конструктор, движок, прежний,
        КонечныеКоманды, безопасный_гит, файл, сырые, внешние, одобрение, начальные_снимки)
    контекст.запустить()
    return 0


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--манифест', required=True)
    разбор.add_argument('--sha256', required=True)
    разбор.add_argument('--этап', required=True, choices=['план', 'выполнить', 'создать', 'повтор', 'cli'])
    разбор.add_argument('--команда')
    разбор.add_argument('--аргументы')
    разбор.add_argument('--одобрение-профиля')
    разбор.add_argument('--sha256-одобрения')
    п = разбор.parse_args()
    try:
        return запустить(п)
    except (ValueError, OSError, KeyError, TypeError, AttributeError, subprocess.SubprocessError) as ошибка:
        traceback.print_exc(file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(главная())

"""Внешний пересмотр ROOT до запуска; исторический prompt B0 не заменяется."""
import copy
import hashlib
import os
from pathlib import Path
import re
import stat

import основание_двусторонней_координации as основание

требовать = основание.требовать
СХЕМА = 'fum.предстартовое-рассмотрение-root.1'


def прочитать_выбор(файл, ожидаемый_хэш):
    """Отдельный выбор вызывающего; собственный SHA файла не даёт полномочий."""
    import подготовка_дочернего_поручения as генератор
    требовать(isinstance(файл, (str, Path)) and type(ожидаемый_хэш) is str
        and re.fullmatch('[0-9a-f]{64}', ожидаемый_хэш) is not None,
        'нужны внешний файл пересмотра и его отдельный SHA-256')
    путь = генератор.этап.приватный(файл)
    родитель = путь.parent.lstat()
    требовать(stat.S_ISDIR(родитель.st_mode) and родитель.st_uid == os.getuid()
        and stat.S_IMODE(родитель.st_mode) == 0o700,
        'пересмотру нужен собственный каталог0700')
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        требовать(stat.S_ISREG(до.st_mode) and до.st_uid == os.getuid()
            and до.st_nlink == 1 and stat.S_IMODE(до.st_mode) == 0o600
            and до.st_size <= 16 * 1024 * 1024, 'необычный файл пересмотра')
        сырые = поток.read(16 * 1024 * 1024 + 1)
        метка = основание.читатель._метка(до)
        требовать(len(сырые) == до.st_size
            and основание.читатель._метка(os.fstat(поток.fileno())) == метка
            and основание.читатель._метка(путь.lstat()) == метка,
            'файл пересмотра изменился при чтении')
    требовать(генератор.хэш(сырые) == ожидаемый_хэш, 'подменён внешний выбор пересмотра')
    данные = генератор.этап.коммит.сообщения._разобрать(сырые)
    генератор.поля(данные, {'схема', 'координатор', 'решение', 'постановка',
        'исторический_контекст', 'координация'})
    требовать(данные['схема'] == СХЕМА, 'неизвестная схема предстартового пересмотра')
    return данные, {'путь': str(путь), 'sha256': ожидаемый_хэш, 'метка': метка}


def сверить_смысл(данные, решение, выбор_решения, выбор_постановки):
    """Пересмотр сохраняет исходные основания, полномочия и префикс B0."""
    старое = решение['координация']
    новое = данные['координация']
    требовать(данные['координатор'] == решение['координатор']
        and данные['решение'] == выбор_решения
        and данные['постановка'] == выбор_постановки
        and данные['исторический_контекст'] == старое['контекст'],
        'пересмотр относится к другой постановке или историческому контексту')
    for ключ in ('экземпляры', 'начало_корня', 'хэш_поручения', 'адресат',
            'сообщения', 'получение', 'ограничения'):
        требовать(новое[ключ] == старое[ключ], 'пересмотр изменяет исходное поручение или основания')
    основание.обработка.проверить_контекст(новое['контекст'])
    ранний = старое['контекст']
    поздний = новое['контекст']
    требовать(поздний['граница'] >= ранний['граница']
        and поздний['экземпляры'][:len(ранний['экземпляры'])] == ранний['экземпляры'],
        'новый контекст не продолжает исходное B0')
    требовать([э for э in новое['решение']['поздние'] if э in set(ранний['экземпляры'])]
        == старое['решение']['поздние'], 'пересмотр потерял прежние уточнения')
    требовать(новое['решение']['область'] == решение['акт']['область'],
        'пересмотр изменяет область исходного поручения')


def _связанные_границы(источник, задача, ранний, поздний, служебный):
    """Одна сырая цепочка хэширования связывает все байты B0 и B1."""
    путь = основание.адреса.точный_абсолютный(источник)
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        идентичность = основание._идентичность(до)
        цепочка = hashlib.sha256()
        требовать(основание._сырой_хэш(поток, 0, ранний['граница'], цепочка)
            == ранний['sha256'], 'B1 не сохраняет исходные байты B0')
        требовать(основание._сырой_хэш(поток, ранний['граница'], поздний['граница'], цепочка)
            == поздний['sha256'], 'границы B0 и B1 не принадлежат общей сырой цепочке')
        основание._завершить_префикс(поток, путь, идентичность, задача,
            поздний, служебный, исходная_метка=основание.читатель._метка(до))


def _проверить(корень, решение, выбор_решения, выбор_постановки, вход,
        файл, ожидаемый_хэш, прочитать_основание, служебный):
    import поздняя_привязка_журнала as поздний
    данные, выбор = прочитать_выбор(файл, ожидаемый_хэш)
    сверить_смысл(данные, решение, выбор_решения, выбор_постановки)
    основание.проверить_рассмотренный_префикс(
        корень, решение, поздний._живой_вход(вход, решение['координация']))
    актуальное = copy.deepcopy(решение)
    актуальное['координация'] = данные['координация']
    проверенное = прочитать_основание(
        корень, актуальное, поздний._живой_вход(вход, данные['координация']))
    _связанные_границы(вход['живой_источник'], решение['координатор'],
        решение['координация']['контекст'], данные['координация']['контекст'], служебный)
    _, повтор = прочитать_выбор(файл, ожидаемый_хэш)
    требовать(повтор == выбор, 'выбор пересмотра изменился во время проверки')
    return {**выбор, 'исторический_контекст': решение['координация']['контекст'],
        'контекст': данные['координация']['контекст'], 'координация': проверенное}


def проверить(корень, решение, выбор_решения, выбор_постановки, вход,
        *, файл, ожидаемый_хэш):
    """B0 проверяется исторически, B1 — полностью с настоящим LIVE-хвостом."""
    return _проверить(корень, решение, выбор_решения, выбор_постановки, вход,
        файл, ожидаемый_хэш, основание.проверить_историческое, True)


def проверить_историю(корень, решение, выбор_решения, выбор_постановки, вход,
        *, файл, ожидаемый_хэш):
    """Только цепочка уже завершённого начала; текущий допуск обеспечивает ACT B2."""
    return _проверить(корень, решение, выбор_решения, выбор_постановки, вход,
        файл, ожидаемый_хэш, основание.проверить_рассмотренный_префикс, False)


def параметры(фаза, файл, ожидаемый_хэш):
    выбрано = файл is not None or ожидаемый_хэш is not None
    требовать(not выбрано or (фаза == 'начало' and файл is not None
        and ожидаемый_хэш is not None), 'пересмотр допустим только для начала с обоими внешними аргументами')
    return выбрано

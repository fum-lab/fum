def байты(значение):
    return (канон.json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode()


class Прерывание(BaseException):
    """Управляемое прерывание процесса для проверки сохранения намерения."""


class ТестовыйАдаптер:
    def __init__(сам, наблюдения, *, сбой=None, ответ=None):
        сам.наблюдения = copy.deepcopy(наблюдения)
        сам.отправки = []
        сам.чтения = 0
        сам.сбой = сбой
        сам.ответ = {"принято": True, "идентификатор": "тест-ответ"} if ответ is None else ответ

    def наблюдать(сам):
        значение = copy.deepcopy(сам.наблюдения[min(сам.чтения, len(сам.наблюдения) - 1)])
        сам.чтения += 1
        return значение

    def отправить(сам, конверт):
        сам.отправки.append(copy.deepcopy(конверт))
        сам.прервать("после отправки")
        return copy.deepcopy(сам.ответ)

    def прервать(сам, точка):
        if сам.сбой == точка:
            raise Прерывание(точка)


ПОЛЯ_ОЖИДАНИЯ = {"схема", "координатор", "задача", "хост", "владелец", "корень", "ref", "HEAD",
    "поручение", "решение_координатора", "поздняя_постановка", "этап", "событие", "ход", "completedAt",
    "модель", "усилие", "текст"}
ПОЛЯ_НАБЛЮДЕНИЯ = {"схема", "координатор", "задача", "хост", "владелец", "корень", "ref", "HEAD",
    "поручение", "решение_координатора", "модель", "усилие", "снимок"}
СВЯЗАННЫЕ = ПОЛЯ_НАБЛЮДЕНИЯ - {"схема", "снимок"}
# Те же широкие корни, которые исключает обычное_поручение.проверить_область.
# Здесь нет файловых целей: отправляется конечный текст в пределах ACT.
ШИРОКИЕ_КОРНИ = {"Журнал", "Индексы", "Правила", "Инструменты", "Планирование",
    "Приложения", "Прототипы", "Документация", "Память", "Источники", "Зависимости"}


def _ответ(ожидание, действие, причина, *, наблюдение=None, запись=None, ход=None):
    новый = ход if ход is not None and ход["id"] != ожидание.get("ход") else None
    return {"схема": "fum.тестовое-восстановление-писателя.1", "действие": действие, "причина": причина,
        "ожидалось": copy.deepcopy(ожидание), "наблюдалось": copy.deepcopy(наблюдение),
        "ответ_отправки": None if запись is None else запись["ответ"],
        "новый_ход": copy.deepcopy(новый), "запуск_этим_намерением": "unknown",
        "завершение_нового_хода": "unknown" if новый is None else
            новый["status"] == "completed" and новый["completedAt"] is not None,
        "приёмка": "unknown", "живой_источник_перепроверен": False,
        "live_send": False, "завершение_всей_работы_доказано": False,
        "граница": "Управляемый тестовый адаптер. Ответ отправки, новый ход, его завершение и приёмка различны. Позднее основание не доказывает машинную связь с bootstrap ACT."}


def _ожидание(значение, корень, профиль):
    канон.поля(значение, ПОЛЯ_ОЖИДАНИЯ)
    канон.требовать(значение["схема"] == "fum.ожидание-восстановления-писателя.1", "неизвестное ожидание")
    for ключ in ("координатор", "задача", "владелец"):
        канон.идентичность(значение[ключ])
    канон.требовать(значение["задача"] == значение["владелец"] != значение["координатор"], "неверный владелец")
    for ключ in ("хост", "ref", "этап", "событие", "ход", "модель", "усилие"):
        канон.строка(значение[ключ])
    канон.строка(значение["корень"])
    канон.требовать(значение["ref"].startswith("refs/heads/codex/"), "нужна собственная ветка codex")
    канон.обычное_поручение._гит(корень, "check-ref-format", значение["ref"])
    канон.полный_хэш(значение["HEAD"], 40)
    канон.требовать(type(значение["completedAt"]) is int and значение["completedAt"] >= 0, "нужно время прерванного хода")
    канон.требовать(type(значение["текст"]) is str and значение["текст"].strip()
        and len(значение["текст"].encode()) <= 65536 and "\x00" not in значение["текст"], "нужен конечный текст")
    канон.требовать(значение["усилие"] in {"none", "minimal", "low", "medium", "high", "xhigh", "max", "ultra"}, "неизвестное усилие")
    акт = канон.прочитать_поручение(корень, значение["поручение"], значение["координатор"], значение["задача"])
    канон.требовать(not any(имя.removesuffix("/") in ШИРОКИЕ_КОРНИ for имя in акт["область"]),
        "широкая служебная область запрещена")
    канон.требовать(акт["координатор"] == значение["координатор"] and акт["исполнитель"] == значение["задача"]
        and акт["ветка"] == значение["ref"], "ACT не совпал с исполнителем/ref")
    канон.прочитать_источник(корень, значение["поздняя_постановка"], профиль)
    return акт


def _наблюдать(ожидание, корень, снимки, адаптер, профиль, *, исходный_ход):
    начало = time.monotonic_ns()
    наблюдение = адаптер.наблюдать()
    канон.поля(наблюдение, ПОЛЯ_НАБЛЮДЕНИЯ)
    канон.требовать(наблюдение["схема"] == "fum.тестовое-наблюдение-писателя.1", "неизвестное наблюдение")
    for ключ in СВЯЗАННЫЕ - {"решение_координатора"}:
        канон.требовать(наблюдение[ключ] == ожидание[ключ], "дрейф наблюдения: " + ключ)
    дерево = канон.физический_путь(ожидание["корень"])
    git_снимок = канон.доставка_план.снимок(дерево, ожидание["владелец"], ожидание["ref"])
    канон.требовать(git_снимок["коммит"] == ожидание["HEAD"], "дрейф фактического HEAD")
    решение = канон.разобрать(канон.прочитать_источник(корень, наблюдение["решение_координатора"], профиль))
    канон.решение_координатора(решение)
    for ключ in ("координатор", "задача", "хост", "владелец", "поручение", "этап", "событие", "ход"):
        канон.требовать(решение[ключ] == ожидание[ключ], "дрейф решения ROOT: " + ключ)
    срез = канон.прочитать_снимок(наблюдение["снимок"], снимки, ожидание["задача"], ожидание["хост"], профиль)
    канон.требовать(срез is not None and наблюдение["снимок"]["курсор_запроса"] is None, "нужен полный адресный latest")
    ход = срез["текущий_ход"]
    канон.требовать(ход is not None, "нет текущего хода")
    действие, причина = None, None
    if решение["состояние"] in ("пауза", "отменён"):
        действие, причина = "ожидание", "поздняя пауза или отмена ROOT"
    elif решение["состояние"] != "открыт" or решение["ожидание"] is not None:
        действие, причина = "адресная сверка", "нет открытого допуска ROOT"
    elif решение["результат"] is not None:
        канон.прочитать_источник(корень, решение["результат"]["источник"], профиль)
        действие = "приёмка поставки" if решение["результат"]["состояние"] == "готов" else "проверить доставку принятого"
        причина = "готовый или принятый результат запрещает повторную реализацию"
    elif наблюдение["решение_координатора"] != ожидание["решение_координатора"]:
        действие, причина = "адресная сверка", "сменился источник решения ROOT"
    elif any(значение != "не было" for значение in решение["эффекты"].values()):
        действие, причина = "адресная сверка", "предыдущий эффект не исключён"
    elif исходный_ход and (ход["id"] != ожидание["ход"] or ход["status"] != "interrupted"
            or ход["completedAt"] != ожидание["completedAt"] or срез["задача"]["status"]["type"] != "idle"
            or срез["задача"]["status"].get("activeFlags")):
        действие, причина = "адресная сверка", "последний прерванный неактивный ход не подтверждён"
    профиль["наблюдение_наносекунды"] += time.monotonic_ns() - начало
    return наблюдение, ход, действие, причина


def _синхронизировать_каталог(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def _записать(путь, значение, *, впервые):
    данные = байты(значение)
    if впервые:
        # O_EXCL и O_NOFOLLOW не превращают повреждённую/чужую запись в отсутствие.
        дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(дескриптор, "wb") as поток:
            поток.write(данные); поток.flush(); os.fsync(поток.fileno())
    else:
        временный = None
        try:
            with tempfile.NamedTemporaryFile(dir=путь.parent, prefix=".ответ-", delete=False) as поток:
                временный = Path(поток.name)
                os.fchmod(поток.fileno(), 0o600)
                поток.write(данные); поток.flush(); os.fsync(поток.fileno())
            os.replace(временный, путь)
        finally:
            if временный is not None and временный.exists():
                временный.unlink()
    _синхронизировать_каталог(путь.parent)


def _прочитать(путь):
    # O_NONBLOCK не даёт FIFO зависнуть до проверки fstat.
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK), "rb") as поток:
        сведения = os.fstat(поток.fileno())
        канон.требовать(stat.S_ISREG(сведения.st_mode) and сведения.st_nlink == 1
            and сведения.st_mode & 0o077 == 0 and сведения.st_size <= 2 * 1024 * 1024, "небезопасная запись намерения")
        данные = поток.read()
    запись = канон.разобрать(данные)
    канон.поля(запись, {"схема", "ключ", "связь", "конверт", "состояние", "ответ"})
    канон.требовать(запись["схема"] == "fum.намерение-тестовой-отправки.1"
        and запись["связь"] == канон.хэш(байты(запись["конверт"]))
        and запись["состояние"] in ("намерение", "ответ"), "повреждено намерение")
    канон.требовать((запись["состояние"] == "намерение") == (запись["ответ"] is None), "повреждено состояние ответа")
    if запись["ответ"] is not None:
        _проверить_ответ(запись["ответ"])
    return запись


def _проверить_ответ(ответ):
    канон.поля(ответ, {"принято", "идентификатор"})
    канон.требовать(type(ответ["принято"]) is bool, "неверный ответ тестовой отправки")
    канон.требовать(ответ["идентификатор"] is None or type(ответ["идентификатор"]) is str
        and bool(ответ["идентификатор"]), "неверный идентификатор ответа")


def восстановить(ожидание, *, корень, каталог_снимков, хранилище, адаптер, профиль=None):
    """Одна попытка только управляемого тестового эффекта; существующее намерение не повторяется.

    Сериализуемые данные не выбирают драйвер, команду или live API. Незавершённый
    замок после настоящего падения требует ручной сверки, а не удаления по timeout.
    """
    начало = time.monotonic_ns()
    измерения = {"прочитано_байтов": 0, "чтений_git_источников": 0, "чтений_снимков": 0,
        "наблюдение_наносекунды": 0, "хранилище_наносекунды": 0, "отправка_наносекунды": 0,
        "тестовых_отправок": 0}
    замок, владеет = None, False
    запись, наблюдение, ход = None, None, None
    try:
        канон.требовать(type(адаптер) is ТестовыйАдаптер, "разрешён только управляемый тестовый адаптер")
        корень = канон.физический_путь(корень)
        снимки = канон.физический_путь(каталог_снимков)
        акт = _ожидание(ожидание, корень, измерения)
        каталог = канон.физический_путь(хранилище)
        канон.требовать(каталог.stat().st_mode & 0o077 == 0, "нужно приватное хранилище")
        дерево = Path(ожидание["корень"])
        канон.требовать(дерево.is_absolute(), "нужен абсолютный checkout")
        канон.требовать(not каталог.is_relative_to(корень) and not каталог.is_relative_to(дерево), "хранилище должно быть вне checkout")
        for checkout in (корень, дерево):
            общий_git = Path(канон.доставка_план.гит(checkout, "rev-parse", "--path-format=absolute", "--git-common-dir")).resolve()
            канон.требовать(not каталог.is_relative_to(общий_git), "хранилище внутри общих Git-данных запрещено")
        ключ = {к: ожидание[к] for к in ("хост", "задача", "ход", "событие", "completedAt", "этап")}
        конверт = {"ожидание": copy.deepcopy(ожидание), "область_ACT": акт["область"],
            "текст_sha256": канон.хэш(ожидание["текст"].encode())}
        связь = канон.хэш(байты(конверт))
        # Перенос хоста также не обходит неопределённое намерение того же UUID.
        имя = канон.хэш(байты({"задача": ожидание["задача"]}))
        путь, замок = каталог / (имя + ".json"), каталог / (имя + ".lock")
        if путь.exists() or путь.is_symlink():
            замер = time.monotonic_ns()
            запись = _прочитать(путь)
            измерения["хранилище_наносекунды"] += time.monotonic_ns() - замер
            if запись["ключ"] != ключ or запись["связь"] != связь:
                return _ответ(ожидание, "сверить исход", "неразрешённое намерение этого исполнителя имеет другую связь", запись=запись)
            наблюдение, ход, действие, причина = _наблюдать(ожидание, корень, снимки, адаптер, измерения, исходный_ход=False)
            return _ответ(ожидание, действие or "сверить исход", причина or "устойчивое намерение запрещает повторную отправку",
                наблюдение=наблюдение, запись=запись, ход=ход)
        try:
            дескриптор = os.open(замок, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        except FileExistsError:
            return _ответ(ожидание, "сверить исход", "замок другого или прерванного процесса; автоматический повтор запрещён")
        os.close(дескриптор); владеет = True
        # Повтор после захвата исключает гонку с завершившимся писателем.
        канон.требовать(not путь.exists() and not путь.is_symlink(), "появилось чужое намерение")
        наблюдение, ход, действие, причина = _наблюдать(ожидание, корень, снимки, адаптер, измерения, исходный_ход=True)
        if действие:
            return _ответ(ожидание, действие, причина, наблюдение=наблюдение, ход=ход)
        адаптер.прервать("до намерения")
        запись = {"схема": "fum.намерение-тестовой-отправки.1", "ключ": ключ, "связь": связь,
            "конверт": конверт, "состояние": "намерение", "ответ": None}
        замер = time.monotonic_ns()
        _записать(путь, запись, впервые=True)
        измерения["хранилище_наносекунды"] += time.monotonic_ns() - замер
        адаптер.прервать("после намерения")
        наблюдение, ход, действие, причина = _наблюдать(ожидание, корень, снимки, адаптер, измерения, исходный_ход=True)
        if действие:
            return _ответ(ожидание, действие, причина, наблюдение=наблюдение, запись=запись, ход=ход)
        замер = time.monotonic_ns()
        измерения["тестовых_отправок"] += 1
        try:
            ответ = адаптер.отправить(конверт)
        finally:
            измерения["отправка_наносекунды"] += time.monotonic_ns() - замер
        адаптер.прервать("перед сохранением ответа")
        _проверить_ответ(ответ)
        новая_запись = {**запись, "состояние": "ответ", "ответ": ответ}
        замер = time.monotonic_ns()
        _записать(путь, новая_запись, впервые=False)
        запись = новая_запись
        измерения["хранилище_наносекунды"] += time.monotonic_ns() - замер
        return _ответ(ожидание, "сверить исход", "ответ отправки сохранён; новый ход и исполнение ещё не доказаны",
            наблюдение=наблюдение, запись=запись, ход=ход)
    except (ValueError, OSError, subprocess.TimeoutExpired, канон.приём_делегации.гит.ОшибкаОтчёта) as ошибка:
        return _ответ(ожидание, "адресная сверка", str(ошибка), наблюдение=наблюдение, запись=запись, ход=ход)
    finally:
        if владеет:
            замок.unlink()
            _синхронизировать_каталог(замок.parent)
        измерения["всего_наносекунды"] = time.monotonic_ns() - начало
        if профиль is not None:
            профиль.update(измерения)

    контракт.требовать(not ошибки, '; '.join(ошибки))
    if граница['схема'] == СХЕМА_СЛИЯНИЯ:
        состав, _ = прочитать_состав(корень, граница['выбранный_состав'])
        дерево = м.дерево_состава(корень, состав)

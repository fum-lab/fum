def проверить_область_записей(параметры):
    """До модельной записи сверяет фактические W-байты с принятым A без recency-правок."""
    м = журнал(); корень = м.физический_корень(Path(параметры['корень']))
    инвентарь_разметки(корень)
    дерево = м._дерево_коммита(корень, параметры['исходный_коммит'])
    начало = {п: з for п, з in дерево.items() if з[1] != 'tree' and not п.startswith('Proyekcii/')}
    разрешённые = set(параметры['разрешённые_цели']) | {м.ПУТЬ_СОСТАВА, м.ПУТЬ_ИНДЕКСА}
    имена = м._гит(корень, 'ls-files', '--cached', '--others', '--exclude-standard', '-z').decode().split('\0')
    текущие = set()
    for имя in filter(None, имена):
        if имя.startswith('Proyekcii/'): continue
        файл = м.точный_путь(корень, имя)
        if not os.path.lexists(файл): continue
        контракт.требовать(имя not in текущие, 'повтор пути текущего diff')
        текущие.add(имя)
        if имя in разрешённые: continue
        контракт.требовать(имя in начало, 'запись вне адресного diff: ' + имя)
        режим, тип, идентификатор_объекта = начало[имя]
        if тип == 'commit':
            запись = м._гит(корень, 'ls-files', '--stage', '-z', '--', имя)
            контракт.требовать(файл.is_dir() and запись == (режим + ' ' + идентификатор_объекта + ' 0\t' + имя).encode() + b'\0',
                'изменён gitlink вне адресной области')
            continue
        сырые, живой_режим = прочитать_обычный_файл(файл)
        алгоритм = hashlib.sha1 if len(идентификатор_объекта) == 40 else hashlib.sha256
        идентификатор_живого_объекта = алгоритм(b'blob ' + str(len(сырые)).encode() + b'\0' + сырые).hexdigest()
        контракт.требовать((живой_режим, 'blob', идентификатор_живого_объекта) == начало[имя],
            'изменение вне адресного diff: ' + имя)
    контракт.требовать(not (set(начало) - текущие - разрешённые), 'удаление вне адресного diff')


def доказательство_слоя(параметры):
    """Доверенный вызывающий контур получает proof только после полных проверок."""
    граница = параметры['привязка_журнала']; сверить_привязку(параметры, граница)
    корень = Path(параметры['корень']); м = журнал(); м.физический_корень(корень)
    данные = параметры['контракт_журнала']
    актуальная = проверить_контракт(корень, данные, выбранный_состав=граница['выбранный_состав'],
        задача=параметры['задача'], писатель=граница['писатель'], запрос=параметры['запрос'])
    контракт.требовать(актуальная == граница, 'стабильная граница изменилась перед proof')
    разрешённые = set(параметры['разрешённые_цели'])
    for имя in разрешённые: контракт.путь(имя)
    ошибки, разметка = проверить_слой_разметки(корень, [корень / п for п in разрешённые],
        дочерняя=параметры['схема'] == 'fum.создание-коммита.10')
    контракт.требовать(not ошибки, '; '.join(ошибки))
    дерево = м._дерево_коммита(корень, граница['принятый_коммит'])
    основа = {п: з for п, з in дерево.items() if з[1] != 'tree' and not п.startswith('Proyekcii/')}
    дерево_начала = м._дерево_коммита(корень, параметры['исходный_коммит'])
    начало = {п: з for п, з in дерево_начала.items() if з[1] != 'tree' and not п.startswith('Proyekcii/')}
    кэш = {}
    for строка in м._гит(корень, 'ls-files', '--stage', '-z').split(b'\0'):
        if not строка: continue
        заголовок, имя = строка.split(b'\t', 1); режим, идентификатор_объекта, стадия = заголовок.decode().split()
        контракт.требовать(стадия == '0' and имя.decode() not in кэш, 'конфликт или повтор индексной записи')
        кэш[имя.decode()] = (режим, идентификатор_объекта)
    имена = м._гит(корень, 'ls-files', '--cached', '--others', '--exclude-standard', '-z').decode().split('\0')
    контракт.требовать(len(list(filter(None, имена))) == len(set(filter(None, имена))), 'повтор пути текущего слоя')
    собственный = str(Path(параметры['запрос']).with_name('отчёт.md'))
    модуль = модуль_свежести(); текущие = {}; наложение = []; отпечаток_отчёта = None
    for имя in filter(None, имена):
        if имя.startswith('Proyekcii/'): continue
        файл = м.точный_путь(корень, имя)
        if not os.path.lexists(файл): continue
        if кэш.get(имя, (None,))[0] == '160000':
            контракт.требовать(файл.is_dir() and начало.get(имя) == ('160000', 'commit', кэш[имя][1]),
                'изменён gitlink вне независимого контракта')
            текущие[имя] = {'путь': имя, 'режим': '160000', 'oid': кэш[имя][1]}
            if основа.get(имя) != начало[имя]:
                наложение.append({'путь': имя, 'было': основа.get(имя), 'стало': текущие[имя]})
            continue
        сырые, режим = прочитать_обычный_файл(файл)
        алгоритм = hashlib.sha1 if len(граница['принятый_коммит']) == 40 else hashlib.sha256
        идентификатор_объекта = алгоритм(b'blob ' + str(len(сырые)).encode() + b'\0' + сырые).hexdigest()
        нормализованные = сырые
        if имя == собственный:
            содержание, мета, повреждён = модуль.split_recency_block(сырые.decode(), путь=файл, корень=корень)
            стабильное, повреждённые_запуски = модуль.стабильное_содержание_отчёта(файл, корень, содержание)
            контракт.требовать(not повреждён and not повреждённые_запуски and мета is not None,
                'повреждён канонический отчёт доказательства')
            нормализованные = контракт.канон({'содержание': стабильное, 'время': мета.timestamp, 'хэш': мета.digest})
            отпечаток_отчёта = контракт.хэш(нормализованные)
        запись = {'путь': имя, 'режим': режим, 'sha256': контракт.хэш(нормализованные)}
        текущие[имя] = запись
        if имя in разметка['разметка_рабочего_дерева']:
            разметка['разметка_рабочего_дерева'][имя] = запись
        if начало.get(имя) != (режим, 'blob', идентификатор_объекта):
            контракт.требовать(имя in разрешённые or имя in {м.ПУТЬ_СОСТАВА, м.ПУТЬ_ИНДЕКСА},
                'наложение вне адресного diff: ' + имя)
        if основа.get(имя) != (режим, 'blob', идентификатор_объекта):
            наложение.append({'путь': имя, 'было': основа.get(имя), 'стало': запись})
    for имя in sorted((set(основа) | set(начало)) - set(текущие)):
        if имя in начало:
            контракт.требовать(имя in разрешённые, 'удаление вне адресного diff: ' + имя)
        if имя in основа: наложение.append({'путь': имя, 'было': основа[имя], 'стало': None})
    контракт.требовать(отпечаток_отчёта is not None, 'нет собственного отчёта полного слоя')
    индексы = [текущие[п] for п in (м.ПУТЬ_СОСТАВА, м.ПУТЬ_ИНДЕКСА, модуль.INDEX_PATH.as_posix())]
    представление = {к: в for к, в in разметка.items() if к != 'разметка_рабочего_дерева'}
    каталоги = [{'путь': п, 'режим': stat.S_IMODE((корень / п).lstat().st_mode)}
        for п, з in sorted(м._живое_дерево(корень).items()) if з[1] == 'tree' and (п == 'Журнал' or п.startswith('Журнал/'))]
    return сверить_доказательство({'схема': СХЕМА_СЛОЯ,
        'контекст_sha256': контекст_слоя(параметры),
        'принятое_представление_sha256': контракт.хэш(контракт.канон(представление)),
        'индексы_sha256': контракт.хэш(контракт.канон(индексы)),
        'разметка_sha256': контракт.хэш(контракт.канон(разметка['разметка_рабочего_дерева'])),
        'наложение_sha256': контракт.хэш(контракт.канон({
            'файлы': sorted(наложение, key=lambda з: з['путь']), 'каталоги_Журнала': каталоги})),
        'отчёт': собственный, 'содержание_отчёта_sha256': отпечаток_отчёта})

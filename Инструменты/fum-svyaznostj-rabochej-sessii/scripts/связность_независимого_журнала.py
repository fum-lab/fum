def проверить_область_записей(параметры, *, выбранный_состав=None):
    """До модельной записи сверяет фактические W-байты с принятым A без recency-правок."""
    м = журнал(); корень = м.физический_корень(Path(параметры['корень']))
    снимки = {}; состав = None; первый_снимок_состава = None
    if выбранный_состав is not None:
        контракт.селектор(выбранный_состав)
        контракт.требовать(параметры['контракт_журнала']['состав'] == выбранный_состав,
            'копия состава не заменяет независимый выбор области')
        состав, сырые = прочитать_состав(корень, выбранный_состав)
        файл = м.точный_путь(корень, м.ПУТЬ_СОСТАВА, существует=True)
        живые, первый_снимок_состава = прочитать_разметку(файл)
        контракт.требовать(живые == сырые, 'живой состав отличается от выбранного Git-источника')
    инвентарь_разметки(корень, состав=состав, снимки=снимки)
    if первый_снимок_состава is not None:
        контракт.требовать(снимки.get(м.ПУТЬ_СОСТАВА) == первый_снимок_состава
            and идентичность_разметки(файл.lstat()) == первый_снимок_состава,
            'состав изменился при инвентаризации области')
        снимки[м.ПУТЬ_СОСТАВА] = первый_снимок_состава
    дерево = м._дерево_коммита(корень, параметры['исходный_коммит'])
    начало = {п: з for п, з in дерево.items() if з[1] != 'tree' and not п.startswith('Proyekcii/')}
    разрешённые = set(параметры['разрешённые_цели']) | {м.ПУТЬ_СОСТАВА, м.ПУТЬ_ИНДЕКСА}
    имена = м._гит(корень, 'ls-files', '--cached', '--others', '--exclude-standard', '-z').decode().split('\0')
    текущие = set()
    for имя in filter(None, имена):
        if имя.startswith('Proyekcii/'): continue
        файл = м.точный_путь(корень, имя)
        if not os.path.lexists(файл): continue
        контракт.требовать(имя not in текущие, 'повтор пути текущего diff')
        текущие.add(имя)
        if имя in разрешённые: continue
        контракт.требовать(имя in начало, 'запись вне адресного diff: ' + имя)
        режим, тип, идентификатор_объекта = начало[имя]
        if тип == 'commit':
            запись = м._гит(корень, 'ls-files', '--stage', '-z', '--', имя)
            контракт.требовать(файл.is_dir() and запись == (режим + ' ' + идентификатор_объекта + ' 0\t' + имя).encode() + b'\0',
                'изменён gitlink вне адресной области')
            continue
        сырые, живой_режим = прочитать_обычный_файл(файл)
        алгоритм = hashlib.sha1 if len(идентификатор_объекта) == 40 else hashlib.sha256
        идентификатор_живого_объекта = алгоритм(b'blob ' + str(len(сырые)).encode() + b'\0' + сырые).hexdigest()
        контракт.требовать((живой_режим, 'blob', идентификатор_живого_объекта) == начало[имя],
            'изменение вне адресного diff: ' + имя)
    контракт.требовать(not (set(начало) - текущие - разрешённые), 'удаление вне адресного diff')
    сверить_снимки_разметки(корень, снимки)


def доказательство_слоя(параметры):
    """Доверенный вызывающий контур получает proof только после полных проверок."""
    граница = параметры['привязка_журнала']; сверить_привязку(параметры, граница)

@contextlib.contextmanager
def чтение_без_обновления_индекса():
    """Канонический checker сохраняется; его Git-чтения не обновляют stat-cache."""
    прежнее = os.environ.get('GIT_OPTIONAL_LOCKS')
    os.environ['GIT_OPTIONAL_LOCKS'] = '0'
    try:
        yield
    finally:
        if прежнее is None: os.environ.pop('GIT_OPTIONAL_LOCKS', None)
        else: os.environ['GIT_OPTIONAL_LOCKS'] = прежнее


@чтение_без_обновления_индекса()
def проверить_полную_свежесть(корень):
    """Прежний полный ROOT check из кода K; W остаётся данными."""
    return модуль_свежести().update_repository(корень, check=True).errors


def проверить_свежесть(корень, пути, *, выбранный_состав=None):
    """Полный старый check H и весь Markdown W; общий индекс W не переписывается."""
    try:
        ошибки, _ = проверить_слой_разметки(корень, пути, выбранный_состав=выбранный_состав)
        return ошибки
    except (OSError, ValueError, UnicodeError) as ошибка:
        ошибки = [str(ошибка)]
        # Отказ выбора S остаётся отказом. Прежняя полная диагностика H
        # всё же должна показать повреждённый индекс, а не скрыть его за S.
        # Рабочая копия здесь только данные диагностики, не источник допуска.
        try:
            м = журнал()
            состав = м._разобрать_данные(м.точный_путь(корень, м.ПУТЬ_СОСТАВА, существует=True).read_bytes())
            м.построить_принятый_индекс(корень, состав)
            ошибки_основы, _, _ = полная_свежесть_основы(корень, состав['коммит'])
            ошибки.extend(ошибки_основы)
        except (OSError, ValueError, UnicodeError, KeyError, TypeError):
            pass
        return ошибки


def проверить_имена_дерева(дерево, пути):
    дети = {}
    for имя in дерево:
        части = Path(имя).parts
        for номер, часть in enumerate(части):
            ключ = ('/'.join(части[:номер]), контракт.ключ_коллизии(часть))
            дети.setdefault(ключ, set()).add(часть)
    for имя in пути:
        контракт.требовать(unicodedata.normalize('NFC', имя) == имя, 'неканонический путь H: ' + имя)
        части = Path(имя).parts
        for номер, часть in enumerate(части):
            контракт.требовать(дети[('/'.join(части[:номер]), контракт.ключ_коллизии(часть))] == {часть},
                'коллизия пути H: ' + имя)


def идентичность_разметки(мета):
    return [мета.st_dev, мета.st_ino, мета.st_mode, мета.st_uid,
        мета.st_nlink, мета.st_size, мета.st_mtime_ns, мета.st_ctime_ns]


def прочитать_разметку(файл, *, материал=None, ожидаемая=None):
    """FD и адрес связывают байты, полный режим, владельца и единственный inode."""
    до = файл.lstat()
    контракт.требовать(stat.S_ISREG(до.st_mode) and до.st_uid == os.getuid()
        and до.st_nlink == 1 and stat.S_IMODE(до.st_mode) in (
            {0o600, 0o644} if материал is not None else {0o644}),
        'необычный Markdown W: ' + str(файл.name))
    снимок = идентичность_разметки(до)
    if ожидаемая is not None:
        контракт.требовать(снимок == ожидаемая, 'дрейф прав или identity Markdown')
    with os.fdopen(os.open(файл, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        контракт.требовать(идентичность_разметки(os.fstat(поток.fileno())) == снимок,
            'подмена Markdown перед чтением')
        данные = поток.read()
        контракт.требовать(идентичность_разметки(os.fstat(поток.fileno())) == снимок,
            'Markdown изменился при чтении')
    контракт.требовать(идентичность_разметки(файл.lstat()) == снимок,
        'подмена адреса Markdown при чтении')
    if материал is not None:
        контракт.требовать(данные == материал, 'подменены байты исторической разметки')
    return данные, снимок


def принятые_материалы_разметки(корень, состав=None, *, снимки=None):
    """Без внешнего контекста S берётся только из неизменного blob родителя HEAD.

    Полный Creator отдельно проверяет независимый выбор S. Его вызывающие
    контуры передают уже проверенный состав; автономный инвентарь не доверяет
    ещё не принятой рабочей копии файла состава.
    """
    м = журнал()
    файл = м.точный_путь(корень, м.ПУТЬ_СОСТАВА)
    if os.path.lexists(файл):
        сырые, снимок = прочитать_разметку(файл)
        if снимки is not None: снимки[м.ПУТЬ_СОСТАВА] = снимок
    if состав is None:
        if not os.path.lexists(файл):
            return {}
        выбранный = {'коммит': м._гит(корень, 'rev-parse', 'HEAD').decode().strip(),
            'путь': м.ПУТЬ_СОСТАВА, 'sha256': контракт.хэш(сырые)}
        состав, _ = прочитать_состав(корень, выбранный)
    else:
        м.построить_принятый_индекс(корень, состав)
    дерево = м._дерево_коммита(корень, состав['коммит'])
    журналы = {з['журнал'] for з in состав['записи']}
    материалы = {}
    for имя, (режим, тип, объект) in дерево.items():
        части = Path(имя).parts
        if (len(части) > 3 and части[0] == 'Журнал' and части[1] in журналы
                and части[2] == 'материалы' and имя.endswith('.md')):
            контракт.требовать(тип == 'blob' and режим == '100644',
                'историческая разметка не является обычным nonexec blob')
            материалы[имя] = объект
    return м._прочитать_объекты(корень, материалы)


def сверить_снимки_разметки(корень, снимки):
    from project_files import is_structurally_excluded
    м = журнал()
    имена = м._гит(корень, 'ls-files', '--cached', '--others', '--exclude-standard', '-z').decode().split('\0')
    текущие = {п for п in имена if п.endswith('.md') and not is_structurally_excluded(п)
        and os.path.lexists(корень / п)}
    контракт.требовать(текущие == {п for п in снимки if п.endswith('.md')},
        'позднее изменение состава Markdown')
    for имя, снимок in снимки.items():
        файл = журнал().точный_путь(корень, имя, существует=True)
        контракт.требовать(идентичность_разметки(файл.lstat()) == снимок,
            'поздний дрейф прав или identity Markdown: ' + имя)


def инвентарь_разметки(корень, *, состав=None, снимки=None):
    """Проверяет кандидатов до отбора regular файлов каноническим project_files."""
    м = журнал()
    from project_files import is_structurally_excluded
    имена = м._гит(корень, 'ls-files', '--cached', '--others', '--exclude-standard', '-z').decode().split('\0')
    результат = {}; материалы = принятые_материалы_разметки(корень, состав, снимки=снимки)
    for имя in имена:
        if not имя or not имя.endswith('.md') or is_structurally_excluded(имя): continue
        контракт.требовать(имя not in результат, 'повтор Markdown пути W: ' + имя)
        файл = м.точный_путь(корень, имя)
        контракт.требовать(unicodedata.normalize('NFC', имя) == имя, 'неканонический Markdown W: ' + имя)
        if not os.path.lexists(файл): continue
        _, снимок = прочитать_разметку(файл, материал=материалы.get(имя))
        if снимки is not None: снимки[имя] = снимок
        результат[имя] = файл
    return результат


def полная_свежесть_основы(корень, коммит):
    """Полный канонический check точных Markdown-данных H, без кода H."""
    м = журнал(); модуль = модуль_свежести(); корень = м.физический_корень(корень)
    дерево = м._дерево_коммита(корень, коммит)
    from project_files import is_structurally_excluded
    имена = {п: з for п, з in дерево.items()
        if п.endswith('.md') and not is_structurally_excluded(п)}
    проверить_имена_дерева(дерево, имена)
    for имя, (режим, тип, _) in имена.items():
        контракт.требовать(тип == 'blob' and режим == '100644'
            and unicodedata.normalize('NFC', имя) == имя, 'необычный Markdown H: ' + имя)
    исходные = м._прочитать_объекты(корень, {п: з[2] for п, з in имена.items()})
    глобальный = модуль.INDEX_PATH.as_posix()
    контракт.требовать(глобальный in исходные, 'нет полного Markdown индекса H: ' + глобальный)
    # Код остаётся в K. Временный каталог содержит только точные MD-данные H,
    # включая исходный индекс; канонический checker не получает .git или код H.
    with tempfile.TemporaryDirectory(prefix='fum-md-H-') as каталог:
        представление = Path(каталог).resolve()
        for имя, данные in исходные.items():
            файл = представление / имя; файл.parent.mkdir(parents=True, exist_ok=True)
            файл.write_bytes(данные); файл.chmod(0o644)
        ошибки = ['H: ' + о for о in модуль.update_repository(представление, check=True, use_git=False).errors]
    return ошибки, имена, исходные



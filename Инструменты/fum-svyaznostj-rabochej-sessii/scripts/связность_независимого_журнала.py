def сверить_доказательство(доказательство):
    новый = type(доказательство) is dict and доказательство.get('схема') == СХЕМА_СЛОЯ
    контракт.поля(доказательство, ПОЛЯ_СЛОЯ | ({'историческая_разметка'} if новый else set()))
    контракт.требовать(доказательство['схема'] in {СХЕМА_СЛОЯ, ПРЕЖНЯЯ_СХЕМА_СЛОЯ},
        'неверное поколение доказательства слоя')
    for имя in ПОЛЯ_СЛОЯ - {'схема', 'отчёт'}: контракт.отпечаток(доказательство[имя])
    контракт.путь(доказательство['отчёт'])
    контракт.требовать(доказательство['отчёт'].startswith('Журнал/')
        and len(Path(доказательство['отчёт']).parts) == 3
        and Path(доказательство['отчёт']).name == 'отчёт.md', 'чужой адрес отчёта доказательства')
    if новый:
        записи = доказательство['историческая_разметка']
        контракт.требовать(type(записи) is list, 'нет снимков исторической разметки')
        имена = []
        for запись in записи:
            контракт.поля(запись, {'путь', 'sha256', 'идентичность'})
            контракт.путь(запись['путь']); контракт.отпечаток(запись['sha256'])
            части = Path(запись['путь']).parts
            контракт.требовать(len(части) > 3 and части[0] == 'Журнал'
                and части[2] == 'материалы' and запись['путь'].endswith('.md'), 'чужой снимок разметки')
            мета = запись['идентичность']
            контракт.требовать(type(мета) is list and len(мета) == 8
                and all(type(п) is int and п >= 0 for п in мета)
                and мета[1] > 0 and мета[2] in {stat.S_IFREG | 0o600, stat.S_IFREG | 0o644}
                and мета[4] == 1, 'неверная фактическая identity исторической разметки')
            имена.append(запись['путь'])
        контракт.требовать(имена == sorted(set(имена)), 'повтор или перестановка исторической разметки')
    return доказательство


def прочитать_обычный_файл(файл):
    with os.fdopen(os.open(файл, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno()); данные = поток.read(); после = os.fstat(поток.fileno())
    контракт.требовать(stat.S_ISREG(до.st_mode)
        and (до.st_dev, до.st_ino, до.st_mode, до.st_size, до.st_mtime_ns)
        == (после.st_dev, после.st_ino, после.st_mode, после.st_size, после.st_mtime_ns),
        'файл изменился при чтении слоя')
    return данные, '100755' if до.st_mode & 0o111 else '100644'



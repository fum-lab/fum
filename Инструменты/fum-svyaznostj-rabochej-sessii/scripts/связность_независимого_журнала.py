def журнал():
    """Отдельное имя исключает коллизию с одноимённым нормативным помощником."""
    имя = 'обычный_независимый_журнал_структуры'
    путь = Path(__file__).absolute().parents[2] / 'fum-struktura-papok-zaprosov/scripts/независимый_журнал.py'
    if имя not in sys.modules:
        родитель = str(путь.parent)
        if родитель not in sys.path: sys.path.insert(0, родитель)
        описание = importlib.util.spec_from_file_location(имя, путь)
        модуль = importlib.util.module_from_spec(описание)
        sys.modules[имя] = модуль
        try: описание.loader.exec_module(модуль)
        except BaseException:
            del sys.modules[имя]
            raise
    модуль = sys.modules[имя]
    контракт.требовать(Path(модуль.__file__).absolute() == путь, 'чужая структура независимого Журнала')
    return модуль


def проверить_план(план):
    м = журнал()
    контракт.поля(план, ПОЛЯ_ПЛАНА)
    контракт.требовать(план['схема'] == м.СХЕМА_ПЛАНА
        and план['разрешение_установки'] is False, 'неверное поколение открытой пары')
    контракт.имя_журнала(план['журнал'])
    контракт.идентичность(план['задача']); контракт.идентичность(план['писатель'])
    контракт.селектор(план['основание']); контракт.отпечаток(план['этап'])
    ожидаемые = ['Журнал/' + план['журнал'] + '/' + часть for часть in ('запрос.md', 'отчёт.md')]
    контракт.требовать(type(план['файлы']) is list and len(план['файлы']) == 2, 'нет двух исходных файлов плана')
    for файл, путь in zip(план['файлы'], ожидаемые):
        контракт.поля(файл, {'путь', 'sha256', 'режим'})
        контракт.отпечаток(файл['sha256'])
        контракт.требовать(файл['путь'] == путь and type(файл['режим']) is int
            and файл['режим'] == 0o644, 'подменён адрес или режим плана пары')
    return план


def прочитать_объект_гита(корень, выбранный):
    м = журнал(); контракт.селектор(выбранный)
    контракт.требовать(м._гит(корень, 'cat-file', '-t', выбранный['коммит']) == b'commit\n',
        'селектор не содержит коммит')
    имя = выбранный['путь']; м.точный_путь(корень, имя)
    запись = м._гит(корень, 'ls-tree', '-z', выбранный['коммит'], '--', имя).split(b'\0')
    контракт.требовать(len(запись) == 2 and запись[1] == b'', 'неоднозначный источник состава')
    мета, путь = запись[0].split(b'\t', 1)
    режим, тип, идентификатор_объекта = мета.decode().split()
    контракт.требовать(путь.decode() == имя and режим == '100644' and тип == 'blob',
        'состав не является точным обычным Git-blob')
    сырые = м._гит(корень, 'cat-file', 'blob', идентификатор_объекта)
    алгоритм = hashlib.sha1 if len(идентификатор_объекта) == 40 else hashlib.sha256
    контракт.требовать(алгоритм(b'blob ' + str(len(сырые)).encode() + b'\0' + сырые).hexdigest() == идентификатор_объекта
        and контракт.хэш(сырые) == выбранный['sha256'], 'подменён Git-источник принятого состава')
    return сырые


def прочитать_состав(корень, выбранный):
    м = журнал(); сырые = прочитать_объект_гита(корень, выбранный)
    состав = м._разобрать_данные(сырые)
    м.построить_принятый_индекс(корень, состав)
    return состав, сырые


_КЛЮЧ_ДОПУСКА_РЕБЁНКА = object()


class _ДопускДочернегоЖурнала:
    """Локальная проверенная связь; не сериализуемый формат и не полномочия Python."""
    __slots__ = ('_ключ', '_параметры', '_поручение', '_состав')

    def __init__(self, ключ, параметры, поручение, состав):
        контракт.требовать(ключ is _КЛЮЧ_ДОПУСКА_РЕБЁНКА, 'нет фабрики допуска ребёнка')
        object.__setattr__(self, '_ключ', ключ)
        object.__setattr__(self, '_параметры', контракт.канон(параметры))
        object.__setattr__(self, '_поручение', контракт.канон(поручение))
        object.__setattr__(self, '_состав', контракт.канон(состав))

    def __setattr__(self, имя, значение):
        raise AttributeError('допуск ребёнка неизменяем')


def _параметры_дочернего_журнала(параметры, доверенное_поручение):
    import создание_коммита as создатель
    контракт.требовать(type(параметры) is dict
        and параметры.get('схема') == 'fum.создание-коммита.10',
        'свежий Git-состав разрешён только полному Maker.10')
    служебные = {'привязка_поручения', 'привязка_журнала'}
    присутствуют = служебные.intersection(параметры)
    контракт.требовать(присутствуют in (set(), служебные), 'неполная пара привязок READY.10')
    основные = {к: з for к, з in параметры.items() if к not in служебные}
    контракт.поля(основные, создатель.ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ
        | {'исполнитель', 'выбранное_поручение', 'контракт_журнала'})
    привязка = создатель.сверить_обычное_поручение(основные,
        доверенное_поручение, новый_эффект=True)
    if присутствуют:
        контракт.требовать(параметры['привязка_поручения'] == привязка,
            'привязка READY не совпадает с независимым ACT')
        сверить_привязку(параметры, параметры['привязка_журнала'])
    данные = основные['контракт_журнала']
    контракт.поля(данные, {'схема', 'открытая', 'состав'})
    контракт.требовать(данные['схема'] == СХЕМА, 'неизвестный контракт ребёнка')
    план = проверить_план(данные['открытая'])
    контракт.требовать(основные['задача'] != основные['исполнитель']
        and os.environ.get('CODEX_THREAD_ID') == основные['исполнитель']
        and план['задача'] == основные['задача']
        and план['писатель'] == основные['исполнитель']
        and основные['запрос'] == 'Журнал/' + план['журнал'] + '/запрос.md',
        'неверная собственная пара ROOT/child')
    import обычное_поручение
    акт = обычное_поручение.прочитать_акт(Path(основные['корень']),
        доверенное_поручение, новый_эффект=True)
    контракт.требовать(акт['схема'] == 'fum.поручение-дочерней-контрольной-точки.1'
        and план['основание'] == акт['постановка'], 'основание пары не равно независимому ACT')
    return основные


def _общие_индексы_основы(корень, исходный_коммит, ветка):
    """Три общих файла и их stage0 обязаны точно совпадать с H."""
    м = журнал(); корень = м.физический_корень(корень)
    контракт.селектор({'коммит': исходный_коммит, 'путь': м.ПУТЬ_СОСТАВА,
        'sha256': '0' * 64})
    контракт.требовать(type(ветка) is str and ветка.startswith('refs/heads/codex/'),
        'нужен полный ref обычного ребёнка')
    контракт.требовать(м._гит(корень, 'rev-parse', '--show-toplevel').decode().strip() == str(корень)
        and м._гит(корень, 'rev-parse', 'HEAD').decode().strip() == исходный_коммит
        and м._гит(корень, 'symbolic-ref', 'HEAD').decode().strip() == ветка,
        'изменилась физическая основа ребёнка')
    имена = (м.ПУТЬ_СОСТАВА, м.ПУТЬ_ИНДЕКСА, модуль_свежести().INDEX_PATH.as_posix())
    дерево = м._дерево_коммита(корень, исходный_коммит)
    for имя in имена:
        контракт.требовать(имя in дерево and дерево[имя][:2] == ('100644', 'blob'),
            'нет обычного общего индекса H: ' + имя)
    ожидаемые = м._прочитать_объекты(корень, {п: дерево[п][2] for п in имена})
    стадия = м._гит(корень, 'ls-files', '--stage', '-z', '--', *имена)
    записи = {}
    for строка in стадия.split(b'\0'):
        if not строка: continue
        заголовок, имя = строка.split(b'\t', 1)
        режим, объект, номер = заголовок.decode().split(); имя = имя.decode()
        контракт.требовать(имя in имена and имя not in записи and номер == '0',
            'конфликт или повтор общего индекса')
        записи[имя] = (режим, 'blob', объект)
    контракт.требовать(записи == {п: дерево[п] for п in имена},
        'stage0 общего индекса отличается от H')
    снимки = {}
    for имя in имена:
        файл = м.точный_путь(корень, имя, существует=True)
        данные, снимки[имя] = прочитать_разметку(файл)
        контракт.требовать(данные == ожидаемые[имя], 'общий индекс W отличается от H: ' + имя)
    контракт.требовать(м._гит(корень, 'ls-files', '--stage', '-z', '--', *имена) == стадия,
        'общие stage0 изменились при чтении')
    for имя, снимок in снимки.items():
        контракт.требовать(идентичность_разметки((корень / имя).lstat()) == снимок,
            'общий индекс изменился при чтении: ' + имя)
    контракт.требовать(м._гит(корень, 'rev-parse', 'HEAD').decode().strip() == исходный_коммит
        and м._гит(корень, 'symbolic-ref', 'HEAD').decode().strip() == ветка,
        'основа ребёнка изменилась при чтении')
    return ожидаемые


def допуск_дочернего_журнала(параметры, доверенное_поручение,
        выбранный_состав, *, новый_эффект=True):
    """Возвращает cap только виртуальному S(H); None сохраняет прежний strict путь.

    None не является положительным результатом проверки Журнала: вызывающий
    контур обязан выполнить прежние liveS/nav, полный Journal, recency и scope.
    Неверные Maker/ACT/native/selector не превращаются в отсутствие capability.
    """
    контракт.требовать(новый_эффект is True, 'исторический повтор не получает нового допуска')
    основные = _параметры_дочернего_журнала(параметры, доверенное_поручение)
    контракт.селектор(выбранный_состав)
    контракт.требовать(основные['контракт_журнала']['состав'] == выбранный_состав,
        'копия S не заменяет внешний выбор ROOT')
    корень = Path(основные['корень']); м = журнал()
    состав, сырые = прочитать_состав(корень, выбранный_состав)
    контракт.требовать(len(м.коммиты_состава(состав)) == 1, 'слияние не является дочерней основой')
    живой = м.точный_путь(корень, м.ПУТЬ_СОСТАВА, существует=True)
    контракт.требовать(stat.S_IMODE(живой.stat().st_mode) == 0o644,
        'необычный режим живого состава')
    if живой.read_bytes() == сырые:
        return None
    контракт.требовать(состав['коммит'] == основные['исходный_коммит'],
        'виртуальный дочерний режим требует S для точного исходного H')
    общие = {м.ПУТЬ_СОСТАВА, м.ПУТЬ_ИНДЕКСА,
        модуль_свежести().INDEX_PATH.as_posix(), 'Журнал/README.md'}
    контракт.требовать(not общие.intersection(основные['разрешённые_цели']),
        'общие индексы и README не входят в T виртуального ребёнка')
    _общие_индексы_основы(корень, основные['исходный_коммит'], основные['ветка'])
    return _ДопускДочернегоЖурнала(_КЛЮЧ_ДОПУСКА_РЕБЁНКА,
        основные, доверенное_поручение, выбранный_состав)


def проверить_допуск_ребёнка(допуск, корень, *, выбранный_состав=None,
        данные=None, параметры=None, состав=None):
    """Заново сверяет independent ACT, точный Maker/H/S и общие W+stage0."""
    контракт.требовать(type(допуск) is _ДопускДочернегоЖурнала
        and допуск._ключ is _КЛЮЧ_ДОПУСКА_РЕБЁНКА, 'нет проверенного допуска ребёнка')
    м = журнал(); корень = м.физический_корень(корень)
    основные = м._разобрать_данные(допуск._параметры)
    поручение = м._разобрать_данные(допуск._поручение)
    внешний = м._разобрать_данные(допуск._состав)
    контракт.требовать(str(корень) == основные['корень'], 'допуск другого worktree')
    _параметры_дочернего_журнала(основные, поручение)
    if параметры is not None:
        текущие = _параметры_дочернего_журнала(параметры, поручение)
        контракт.требовать(контракт.канон(текущие) == допуск._параметры,
            'допуск не связан с полным текущим Maker.10')
    if выбранный_состав is not None:
        контракт.требовать(выбранный_состав == внешний, 'подменён независимый S допуска')
    if данные is not None:
        контракт.требовать(данные == основные['контракт_журнала'], 'подменён контракт собственного Журнала')
    принятое, сырые = прочитать_состав(корень, внешний)
    контракт.требовать(len(м.коммиты_состава(принятое)) == 1, 'слияние не является дочерней основой')
    контракт.требовать(принятое['коммит'] == основные['исходный_коммит'],
        'S не описывает исходный H ребёнка')
    if состав is not None:
        контракт.требовать(состав == принятое, 'подменён разобранный состав ребёнка')
    индексы = _общие_индексы_основы(корень, основные['исходный_коммит'], основные['ветка'])
    return {'параметры': основные, 'выбранный_состав': внешний,
        'состав': принятое, 'сырые_состава': сырые, 'индексы': индексы}


def проверить_основу_дочернего_журнала(корень, состав, *, допуск_ребёнка=None):
    """Без cap выполняется прежний strict mixed; None не отменяет его проверок."""
    if допуск_ребёнка is not None:
        проверить_допуск_ребёнка(допуск_ребёнка, корень, состав=состав)
    return журнал().проверить_смешанный(корень, состав, допуск_ребёнка=допуск_ребёнка)


def проверить_читаемую_основу(корень, выбранный_состав, *, исходный_коммит, ветка):
    """До ACT: данные D/native проверяет вызывающий; результат не является cap.

    Установленный Git S сохраняет прежний полный strict mixed без нового
    равенства S.коммит == H. Только виртуальная ветвь требует H-exact индексы.
    """
    м = журнал(); корень = м.физический_корень(корень)
    состав, сырые = прочитать_состав(корень, выбранный_состав)
    контракт.требовать(len(м.коммиты_состава(состав)) == 1, 'слияние не является дочерней основой')
    живой = м.точный_путь(корень, м.ПУТЬ_СОСТАВА, существует=True)
    контракт.требовать(stat.S_IMODE(живой.stat().st_mode) == 0o644,
        'необычный режим живого состава')
    if живой.read_bytes() == сырые:
        return м.проверить_смешанный(корень, состав)
    контракт.требовать(состав['коммит'] == исходный_коммит, 'виртуальный читаемый S не покрывает выбранный H')
    индексы = _общие_индексы_основы(корень, исходный_коммит, ветка)
    результат = м._проверить_смешанный_с_навигацией(корень, состав,
        навигация_основы=индексы[м.ПУТЬ_ИНДЕКСА])
    ошибки, _, _ = полная_свежесть_основы(корень, исходный_коммит)
    контракт.требовать(not ошибки, '; '.join(ошибки))
    контракт.требовать(_общие_индексы_основы(корень, исходный_коммит, ветка) == индексы,
        'читаемые общие индексы изменились')
    return результат


def проверить_контракт(корень, данные, *, выбранный_состав, задача, писатель, запрос,
        допуск_ребёнка=None):
    """Только чтение; стабильная привязка не включает mutable отчёт открытой пары."""
    try:
        контракт.поля(данные, {'схема', 'открытая', 'состав'})
        контракт.требовать(данные['схема'] in {СХЕМА, СХЕМА_СЛИЯНИЯ}, 'неизвестный контракт независимой точки')
        контракт.селектор(выбранный_состав)
        контракт.требовать(данные['состав'] == выбранный_состав,
            'нет совпадающего независимого выбора принятого состава')
        контракт.идентичность(задача); контракт.идентичность(писатель)
        контракт.требовать(os.environ.get('CODEX_THREAD_ID') == писатель, 'чужая среда писателя Журнала')
        план = проверить_план(данные['открытая'])
        контракт.требовать(план['задача'] == задача and план['писатель'] == писатель
            and запрос == '/'.join(('Журнал', план['журнал'], 'запрос.md')), 'чужая адресная граница пары')
        м = журнал(); м._ресурсы()
        прочитать_объект_гита(корень, план['основание'])
        состав, сырые = прочитать_состав(корень, выбранный_состав)
        коммиты = м.коммиты_состава(состав)
        контракт.требовать((данные['схема'] == СХЕМА_СЛИЯНИЯ) == (len(коммиты) == 2),
            'схема контракта не соответствует источникам состава')
        if len(коммиты) == 2:
            контракт.требовать(задача == писатель and допуск_ребёнка is None,
                'слияние требует собственного ROOT')
            _сверить_родителей_слияния(корень, коммиты)
        if допуск_ребёнка is None:
            живой = м.точный_путь(корень, м.ПУТЬ_СОСТАВА, существует=True)
            контракт.требовать(stat.S_IMODE(живой.stat().st_mode) == 0o644
                and живой.read_bytes() == сырые, 'живой состав отличается от выбранного Git-источника')
        else:
            допущено = проверить_допуск_ребёнка(допуск_ребёнка, корень,
                выбранный_состав=выбранный_состав, данные=данные, состав=состав)
            собственные = допущено['параметры']
            контракт.требовать((задача, писатель, запрос) == (собственные['задача'],
                собственные['исполнитель'], собственные['запрос']), 'чужая идентичность контракта ребёнка')
        результат = м.проверить_смешанный(корень, состав, открытая=план,
            допуск_ребёнка=допуск_ребёнка)
        for файл in план['файлы']:
            путь = м.точный_путь(корень, файл['путь'], существует=True)
            контракт.требовать(stat.S_IMODE(путь.stat().st_mode) == 0o644, 'необычный режим открытой пары')
        return {'схема': данные['схема'], 'выбранный_состав': выбранный_состав,
            'контракт_sha256': контракт.хэш(контракт.канон(данные)),
            'план_sha256': контракт.хэш(контракт.канон(план)),
            'этап': план['этап'], 'задача': задача, 'писатель': писатель,
            'запрос': запрос, **_основание_привязки(корень, состав),
            'состав_sha256': результат['состав_sha256']}
    except (KeyError, TypeError, OSError, UnicodeError) as ошибка:
        raise ValueError('неполная или недоступная независимая граница') from ошибка


def сверить_команды(данные, команды):
    план = проверить_план(данные['открытая'])
    контракт.требовать(type(команды) is list and команды
        and all(type(к) is dict and type(к.get('текст')) is str for к in команды),
        'нет первичных команд независимого этапа')
    свойства = {к: план[к] for к in ('журнал', 'задача', 'писатель', 'основание')}
    ожидаемый = контракт.хэш(контракт.канон({**свойства, 'команды': [к['текст'] for к in команды]}))
    контракт.требовать(план['этап'] == ожидаемый, 'этап не соответствует исходным командам и повторам')


def сверить_привязку(параметры, граница):
    """Чистая проверка закрытой обёртки; live Git повторно читает Creator."""
    слияние = type(граница) is dict and граница.get('схема') == СХЕМА_СЛИЯНИЯ
    поля_источников = {'принятые_коммиты', 'принятые_деревья'} if слияние else {'принятый_коммит'}
    контракт.поля(граница, {'схема', 'выбранный_состав', 'контракт_sha256', 'план_sha256',
        'этап', 'задача', 'писатель', 'запрос', 'состав_sha256'} | поля_источников)
    данные = параметры.get('контракт_журнала')
    контракт.поля(данные, {'схема', 'открытая', 'состав'})
    контракт.требовать(данные['схема'] == граница['схема'] == (СХЕМА_СЛИЯНИЯ if слияние else СХЕМА), 'неверная схема привязки')
    план = проверить_план(данные['открытая'])
    контракт.селектор(данные['состав']); контракт.селектор(граница['выбранный_состав'])
    if слияние:
        коммиты = журнал().объединение.проверить_коммиты(граница['принятые_коммиты'], контракт)
        деревья = граница['принятые_деревья']
        контракт.требовать(type(деревья) is list and len(деревья) == 2,
            'нет двух принятых деревьев')
        for дерево in деревья:
            контракт.селектор({'коммит': дерево, 'путь': 'Журнал/README.md',
                'sha256': граница['состав_sha256']})
        контракт.требовать(параметры['схема'] == 'fum.создание-коммита.9'
            and параметры['родители'] == коммиты and параметры['исходный_коммит'] == коммиты[0],
            'состав слияния не совпадает с ROOT Maker и родителями')
    else:
        контракт.селектор({'коммит': граница['принятый_коммит'], 'путь': 'Журнал/README.md',
            'sha256': граница['состав_sha256']})
    писатель = параметры['задача'] if параметры['схема'] == 'fum.создание-коммита.9' else параметры['исполнитель']
    контракт.идентичность(писатель); контракт.идентичность(параметры['задача'])
    контракт.требовать(граница['задача'] == план['задача'] == параметры['задача']
        and граница['писатель'] == план['писатель'] == писатель
        and (параметры['схема'] != 'fum.создание-коммита.10' or писатель != параметры['задача'])
        and граница['запрос'] == параметры['запрос'] == '/'.join(('Журнал', план['журнал'], 'запрос.md'))
        and граница['этап'] == план['этап'] and граница['выбранный_состав'] == данные['состав']
        and граница['контракт_sha256'] == контракт.хэш(контракт.канон(данные))
        and граница['план_sha256'] == контракт.хэш(контракт.канон(план)), 'подменена проверенная привязка Журнала')
    for имя in ('контракт_sha256', 'план_sha256', 'этап', 'состав_sha256'):
        контракт.отпечаток(граница[имя])
    return граница



def _основание_привязки(корень, состав):
    м = журнал()
    коммиты = м.коммиты_состава(состав)

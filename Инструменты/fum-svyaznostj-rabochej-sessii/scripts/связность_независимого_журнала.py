def журнал():
    """Отдельное имя исключает коллизию с одноимённым нормативным помощником."""
    имя = 'обычный_независимый_журнал_структуры'
    путь = Path(__file__).absolute().parents[2] / 'fum-struktura-papok-zaprosov/scripts/независимый_журнал.py'
    if имя not in sys.modules:
        родитель = str(путь.parent)
        if родитель not in sys.path: sys.path.insert(0, родитель)
        описание = importlib.util.spec_from_file_location(имя, путь)
        модуль = importlib.util.module_from_spec(описание)
        sys.modules[имя] = модуль
        try: описание.loader.exec_module(модуль)
        except BaseException:
            del sys.modules[имя]
            raise
    модуль = sys.modules[имя]
    контракт.требовать(Path(модуль.__file__).absolute() == путь, 'чужая структура независимого Журнала')
    return модуль


def проверить_план(план):
    м = журнал()
    контракт.поля(план, ПОЛЯ_ПЛАНА)
    контракт.требовать(план['схема'] == м.СХЕМА_ПЛАНА
        and план['разрешение_установки'] is False, 'неверное поколение открытой пары')
    контракт.имя_журнала(план['журнал'])
    контракт.идентичность(план['задача']); контракт.идентичность(план['писатель'])
    контракт.селектор(план['основание']); контракт.отпечаток(план['этап'])
    ожидаемые = ['Журнал/' + план['журнал'] + '/' + часть for часть in ('запрос.md', 'отчёт.md')]
    контракт.требовать(type(план['файлы']) is list and len(план['файлы']) == 2, 'нет двух исходных файлов плана')
    for файл, путь in zip(план['файлы'], ожидаемые):
        контракт.поля(файл, {'путь', 'sha256', 'режим'})
        контракт.отпечаток(файл['sha256'])
        контракт.требовать(файл['путь'] == путь and type(файл['режим']) is int
            and файл['режим'] == 0o644, 'подменён адрес или режим плана пары')
    return план


def прочитать_объект_гита(корень, выбранный):
    м = журнал(); контракт.селектор(выбранный)
    контракт.требовать(м._гит(корень, 'cat-file', '-t', выбранный['коммит']) == b'commit\n',
        'селектор не содержит коммит')
    имя = выбранный['путь']; м.точный_путь(корень, имя)
    запись = м._гит(корень, 'ls-tree', '-z', выбранный['коммит'], '--', имя).split(b'\0')
    контракт.требовать(len(запись) == 2 and запись[1] == b'', 'неоднозначный источник состава')
    мета, путь = запись[0].split(b'\t', 1)
    режим, тип, идентификатор_объекта = мета.decode().split()
    контракт.требовать(путь.decode() == имя and режим == '100644' and тип == 'blob',
        'состав не является точным обычным Git-blob')
    сырые = м._гит(корень, 'cat-file', 'blob', идентификатор_объекта)
    алгоритм = hashlib.sha1 if len(идентификатор_объекта) == 40 else hashlib.sha256
    контракт.требовать(алгоритм(b'blob ' + str(len(сырые)).encode() + b'\0' + сырые).hexdigest() == идентификатор_объекта
        and контракт.хэш(сырые) == выбранный['sha256'], 'подменён Git-источник принятого состава')
    return сырые


def прочитать_состав(корень, выбранный):
    м = журнал(); сырые = прочитать_объект_гита(корень, выбранный)
    состав = м._разобрать_данные(сырые)
    м.построить_принятый_индекс(корень, состав)
    return состав, сырые


def проверить_контракт(корень, данные, *, выбранный_состав, задача, писатель, запрос):
    """Только чтение; стабильная привязка не включает mutable отчёт открытой пары."""
    try:
        контракт.поля(данные, {'схема', 'открытая', 'состав'})
        контракт.требовать(данные['схема'] == СХЕМА, 'неизвестный контракт независимой точки')
        контракт.селектор(выбранный_состав)
        контракт.требовать(данные['состав'] == выбранный_состав,
            'нет совпадающего независимого выбора принятого состава')
        контракт.идентичность(задача); контракт.идентичность(писатель)
        контракт.требовать(os.environ.get('CODEX_THREAD_ID') == писатель, 'чужая среда писателя Журнала')
        план = проверить_план(данные['открытая'])
        контракт.требовать(план['задача'] == задача and план['писатель'] == писатель
            and запрос == '/'.join(('Журнал', план['журнал'], 'запрос.md')), 'чужая адресная граница пары')
        м = журнал(); м._ресурсы()
        прочитать_объект_гита(корень, план['основание'])
        состав, сырые = прочитать_состав(корень, выбранный_состав)
        живой = м.точный_путь(корень, м.ПУТЬ_СОСТАВА, существует=True)
        контракт.требовать(stat.S_IMODE(живой.stat().st_mode) == 0o644
            and живой.read_bytes() == сырые, 'живой состав отличается от выбранного Git-источника')
        результат = м.проверить_смешанный(корень, состав, открытая=план)
        for файл in план['файлы']:
            путь = м.точный_путь(корень, файл['путь'], существует=True)
            контракт.требовать(stat.S_IMODE(путь.stat().st_mode) == 0o644, 'необычный режим открытой пары')
        return {'схема': СХЕМА, 'выбранный_состав': выбранный_состав,
            'контракт_sha256': контракт.хэш(контракт.канон(данные)),
            'план_sha256': контракт.хэш(контракт.канон(план)),
            'этап': план['этап'], 'задача': задача, 'писатель': писатель,
            'запрос': запрос, 'принятый_коммит': состав['коммит'],
            'состав_sha256': результат['состав_sha256']}
    except (KeyError, TypeError, OSError, UnicodeError) as ошибка:
        raise ValueError('неполная или недоступная независимая граница') from ошибка


def сверить_команды(данные, команды):
    план = проверить_план(данные['открытая'])
    контракт.требовать(type(команды) is list and команды
        and all(type(к) is dict and type(к.get('текст')) is str for к in команды),
        'нет первичных команд независимого этапа')
    свойства = {к: план[к] for к in ('журнал', 'задача', 'писатель', 'основание')}
    ожидаемый = контракт.хэш(контракт.канон({**свойства, 'команды': [к['текст'] for к in команды]}))
    контракт.требовать(план['этап'] == ожидаемый, 'этап не соответствует исходным командам и повторам')


def сверить_привязку(параметры, граница):
    """Чистая проверка закрытой обёртки; live Git повторно читает Creator."""
    контракт.поля(граница, {'схема', 'выбранный_состав', 'контракт_sha256', 'план_sha256',
        'этап', 'задача', 'писатель', 'запрос', 'принятый_коммит', 'состав_sha256'})
    данные = параметры.get('контракт_журнала')
    контракт.поля(данные, {'схема', 'открытая', 'состав'})
    контракт.требовать(данные['схема'] == граница['схема'] == СХЕМА, 'неверная схема привязки')
    план = проверить_план(данные['открытая'])
    контракт.селектор(данные['состав']); контракт.селектор(граница['выбранный_состав'])
    контракт.селектор({'коммит': граница['принятый_коммит'], 'путь': 'Журнал/README.md',
        'sha256': граница['состав_sha256']})
    писатель = параметры['задача'] if параметры['схема'] == 'fum.создание-коммита.9' else параметры['исполнитель']
    контракт.идентичность(писатель); контракт.идентичность(параметры['задача'])
    контракт.требовать(граница['задача'] == план['задача'] == параметры['задача']
        and граница['писатель'] == план['писатель'] == писатель
        and (параметры['схема'] != 'fum.создание-коммита.10' or писатель != параметры['задача'])
        and граница['запрос'] == параметры['запрос'] == '/'.join(('Журнал', план['журнал'], 'запрос.md'))
        and граница['этап'] == план['этап'] and граница['выбранный_состав'] == данные['состав']
        and граница['контракт_sha256'] == контракт.хэш(контракт.канон(данные))
        and граница['план_sha256'] == контракт.хэш(контракт.канон(план)), 'подменена проверенная привязка Журнала')
    for имя in ('контракт_sha256', 'план_sha256', 'этап', 'состав_sha256'):
        контракт.отпечаток(граница[имя])
    return граница



def проверить_свежесть(корень, пути):
    """Полный старый check H и весь Markdown W; общий индекс W не переписывается."""
    try:
        ошибки, _ = проверить_слой_разметки(корень, пути)
        return ошибки
    except (OSError, ValueError, UnicodeError) as ошибка:
        return [str(ошибка)]


def проверить_имена_дерева(дерево, пути):
    дети = {}
    for имя in дерево:
        части = Path(имя).parts
        for номер, часть in enumerate(части):
            ключ = ('/'.join(части[:номер]), контракт.ключ_коллизии(часть))
            дети.setdefault(ключ, set()).add(часть)
    for имя in пути:
        контракт.требовать(unicodedata.normalize('NFC', имя) == имя, 'неканонический путь H: ' + имя)
        части = Path(имя).parts
        for номер, часть in enumerate(части):
            контракт.требовать(дети[('/'.join(части[:номер]), контракт.ключ_коллизии(часть))] == {часть},
                'коллизия пути H: ' + имя)


def инвентарь_разметки(корень):
    """Проверяет кандидатов до отбора regular файлов каноническим project_files."""
    м = журнал()
    from project_files import is_structurally_excluded
    имена = м._гит(корень, 'ls-files', '--cached', '--others', '--exclude-standard', '-z').decode().split('\0')
    результат = {}
    for имя in имена:
        if not имя or not имя.endswith('.md') or is_structurally_excluded(имя): continue
        контракт.требовать(имя not in результат, 'повтор Markdown пути W: ' + имя)
        файл = м.точный_путь(корень, имя)
        контракт.требовать(unicodedata.normalize('NFC', имя) == имя, 'неканонический Markdown W: ' + имя)
        if not os.path.lexists(файл): continue
        контракт.требовать(stat.S_ISREG(файл.lstat().st_mode)
            and stat.S_IMODE(файл.lstat().st_mode) == 0o644, 'необычный Markdown W: ' + имя)
        результат[имя] = файл
    return результат


def полная_свежесть_основы(корень, коммит):
    """Полный канонический check точных Markdown-данных H, без кода H."""
    м = журнал(); модуль = модуль_свежести(); корень = м.физический_корень(корень)
    дерево = м._дерево_коммита(корень, коммит)
    from project_files import is_structurally_excluded
    имена = {п: з for п, з in дерево.items()
        if п.endswith('.md') and not is_structurally_excluded(п)}
    проверить_имена_дерева(дерево, имена)
    for имя, (режим, тип, _) in имена.items():
        контракт.требовать(тип == 'blob' and режим == '100644'
            and unicodedata.normalize('NFC', имя) == имя, 'необычный Markdown H: ' + имя)
    исходные = м._прочитать_объекты(корень, {п: з[2] for п, з in имена.items()})
    глобальный = модуль.INDEX_PATH.as_posix()
    контракт.требовать(глобальный in исходные, 'нет полного Markdown индекса H: ' + глобальный)
    # Код остаётся в K. Временный каталог содержит только точные MD-данные H,
    # включая исходный индекс; канонический checker не получает .git или код H.
    with tempfile.TemporaryDirectory(prefix='fum-md-H-') as каталог:
        представление = Path(каталог).resolve()
        for имя, данные in исходные.items():
            файл = представление / имя; файл.parent.mkdir(parents=True, exist_ok=True)
            файл.write_bytes(данные); файл.chmod(0o644)
        ошибки = ['H: ' + о for о in модуль.update_repository(представление, check=True, use_git=False).errors]
    return ошибки, имена, исходные


def проверить_слой_разметки(корень, пути, *, дочерняя=True):
    м = журнал(); модуль = модуль_свежести(); корень = м.физический_корень(корень)
    состав = м._разобрать_данные(м.точный_путь(корень, м.ПУТЬ_СОСТАВА, существует=True).read_bytes())
    индекс = м.построить_принятый_индекс(корень, состав)
    ошибки, имена, исходные = полная_свежесть_основы(корень, состав['коммит'])
    глобальный = модуль.INDEX_PATH.as_posix()
    собственные = {Path(п).relative_to(корень).as_posix() for п in пути}
    текущие = {}; сейчас = модуль.format_msk(модуль.parse_now())
    безопасные = инвентарь_разметки(корень)
    контракт.требовать(set(безопасные.values()) == set(модуль.project_markdown_paths(корень)),
        'неполный фактический инвентарь Markdown W')
    for файл in безопасные.values():
        имя = файл.relative_to(корень).as_posix(); контракт.путь(имя)
        м.точный_путь(корень, имя, существует=True)
        контракт.требовать(unicodedata.normalize('NFC', имя) == имя
            and stat.S_IMODE(файл.lstat().st_mode) == 0o644, 'необычный Markdown W: ' + имя)
        данные = файл.read_bytes(); текущие[имя] = {'путь': имя, 'режим': '100644', 'sha256': контракт.хэш(данные)}
        _, найденные, _ = модуль.process_markdown_file(файл, корень, set(), сейчас, True, False)
        ошибки.extend(найденные)
        if имя == глобальный:
            if дочерняя and данные != исходные[имя]: ошибки.append('Markdown индекс W отличается от принятого H: ' + имя)
        elif имя == м.ПУТЬ_ИНДЕКСА:
            if данные != индекс['байты']: ошибки.append('неверная производная навигация: ' + имя)
        elif имя not in собственные:
            if имя not in исходные or данные != исходные[имя]:
                ошибки.append('постороннее изменение Markdown вне адресной области: ' + имя)
    for имя in sorted(set(исходные) - set(текущие)):
        ошибки.append('отсутствует принятый Markdown W: ' + имя)
    if not дочерняя:
        ошибки.extend(модуль.update_repository(корень, check=True).errors)
    основа = [{'путь': п, 'режим': имена[п][0], 'sha256': контракт.хэш(д)} for п, д in sorted(исходные.items())]
    return ошибки, {'коммит': состав['коммит'],
        'дерево': м._гит(корень, 'rev-parse', состав['коммит'] + '^{tree}').decode().strip(),
        'разметка_основы_sha256': контракт.хэш(контракт.канон(основа)),
        'индекс_основы_sha256': контракт.хэш(исходные[глобальный]),
        'разметка_рабочего_дерева': текущие}


СХЕМА_СЛОЯ = 'fum.доказательство-наложения-независимого-журнала.1'
ПОЛЯ_СЛОЯ = {'схема', 'контекст_sha256', 'принятое_представление_sha256',
    'индексы_sha256', 'разметка_sha256', 'наложение_sha256', 'отчёт', 'содержание_отчёта_sha256'}


def сверить_доказательство(доказательство):
    контракт.поля(доказательство, ПОЛЯ_СЛОЯ)
    контракт.требовать(доказательство['схема'] == СХЕМА_СЛОЯ, 'неверное поколение доказательства слоя')
    for имя in ПОЛЯ_СЛОЯ - {'схема', 'отчёт'}: контракт.отпечаток(доказательство[имя])
    контракт.путь(доказательство['отчёт'])
    контракт.требовать(доказательство['отчёт'].startswith('Журнал/')
        and len(Path(доказательство['отчёт']).parts) == 3
        and Path(доказательство['отчёт']).name == 'отчёт.md', 'чужой адрес отчёта доказательства')
    return доказательство


def прочитать_обычный_файл(файл):
    with os.fdopen(os.open(файл, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno()); данные = поток.read(); после = os.fstat(поток.fileno())
    контракт.требовать(stat.S_ISREG(до.st_mode)
        and (до.st_dev, до.st_ino, до.st_mode, до.st_size, до.st_mtime_ns)
        == (после.st_dev, после.st_ino, после.st_mode, после.st_size, после.st_mtime_ns),
        'файл изменился при чтении слоя')
    return данные, '100755' if до.st_mode & 0o111 else '100644'


def контекст_слоя(параметры):
    граница = параметры['привязка_журнала']; сверить_привязку(параметры, граница)
    м = журнал(); корень = м.физический_корень(Path(параметры['корень']))

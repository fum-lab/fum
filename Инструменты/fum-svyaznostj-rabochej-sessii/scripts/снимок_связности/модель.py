"""Замкнутые значения без ссылок на изменяемые контейнеры или checkout."""
from dataclasses import dataclass, fields, is_dataclass
import hashlib
import json
from pathlib import PurePosixPath
import re


class НеполныйСнимок(RuntimeError):
    """Неизвестность не является ни отсутствием файла, ни ошибкой ссылки."""


def упаковать(значение):
    if type(значение) in (str, int, bool) or значение is None:
        return значение
    if type(значение) is bytes:
        return {'байты': значение.hex()}
    if type(значение) is tuple:
        return [упаковать(элемент) for элемент in значение]
    if is_dataclass(значение) and type(значение) in (Наблюдение, Кандидат, Снимок, Результат):
        return {поле.name: упаковать(getattr(значение, поле.name)) for поле in fields(значение) if поле.name != 'sha256'}
    raise НеполныйСнимок('неизвестный или изменяемый тип снимка')


def хэш(значение):
    return hashlib.sha256(json.dumps(упаковать(значение), ensure_ascii=False,
        sort_keys=True, separators=(',', ':')).encode()).hexdigest()


@dataclass(frozen=True)
class Наблюдение:
    операция: str
    путь: str
    значение: object


@dataclass(frozen=True)
class Кандидат:
    путь: str
    происхождение: str
    состояние: tuple
    удаление: str


@dataclass(frozen=True)
class Снимок:
    схема: str
    вызов: str
    корень: str
    выбранные: tuple
    инвентарь: tuple
    тексты: tuple
    наблюдения: tuple
    код: tuple
    параметры: tuple
    полный: bool
    sha256: str


@dataclass(frozen=True)
class Результат:
    вызов: str
    снимок: str
    ошибки: tuple


def проверить_модель(снимок):
    if type(снимок) is not Снимок or снимок.схема != 'fum.снимок-ссылок.1' or снимок.полный is not True:
        raise НеполныйСнимок('нет полного снимка известной схемы')
    if хэш(снимок) != снимок.sha256:
        raise НеполныйСнимок('изменены байты или поля снимка')
    if not снимок.вызов or not снимок.корень.startswith('/'):
        raise НеполныйСнимок('нет адреса вызова или физического корня')
    ключи = [(запись.операция, запись.путь) for запись in снимок.наблюдения]
    if len(set(ключи)) != len(ключи):
        raise НеполныйСнимок('повтор ключа наблюдений')
    if not re.fullmatch(r'[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}', снимок.вызов):
        raise НеполныйСнимок('неверный адрес вызова')
    наблюдения = {}
    for запись in снимок.наблюдения:
        if type(запись) is not Наблюдение or not запись.путь.startswith('/'):
            raise НеполныйСнимок('неверная запись наблюдения')
        оп, значение = запись.операция, запись.значение
        тип = type(значение)
        допустимо = (
            оп == 'read_bytes' and тип is bytes
            or оп == 'resolve' and тип is str and значение.startswith('/')
            or оп in ('exists', 'is_dir', 'is_symlink') and тип is bool
            or оп == 'stat' and (значение is None or тип is int)
            or оп == 'iterdir' and (значение is None or тип is tuple and all(type(элемент) is str and элемент.startswith('/') for элемент in значение))
            or оп == 'узел' and тип is tuple and значение and значение[0] in ('отсутствует', 'файл', 'каталог', 'ссылка', 'иной'))
        if not допустимо: raise НеполныйСнимок('неизвестный исход наблюдения')
        наблюдения[оп, запись.путь] = значение
    for запись in снимок.наблюдения:
        узел = наблюдения.get(('узел', запись.путь))
        if узел is not None and узел[0] != 'ссылка':
            if запись.операция == 'exists' and запись.значение != (узел[0] != 'отсутствует'):
                raise НеполныйСнимок('противоречивое наблюдение существования')
            if запись.операция == 'is_dir' and запись.значение != (узел[0] == 'каталог'):
                raise НеполныйСнимок('противоречивое наблюдение каталога')
            if запись.операция == 'is_symlink' and запись.значение is not False:
                raise НеполныйСнимок('противоречивое наблюдение ссылки')
        if запись.операция == 'iterdir' and запись.значение is not None:
            дети = запись.значение
            if tuple(sorted(set(дети))) != дети:
                raise НеполныйСнимок('неполный или повторённый состав каталога')
            for ребёнок in дети:
                if str(PurePosixPath(ребёнок).parent) != запись.путь or ('узел', ребёнок) not in наблюдения:
                    raise НеполныйСнимок('не удержан тип дочернего пути')
    кандидаты = {}
    for кандидат in снимок.инвентарь:
        if type(кандидат) is not Кандидат or кандидат.происхождение not in ('tracked', 'untracked', 'filesystem'):
            raise НеполныйСнимок('неизвестное происхождение кандидата')
        if кандидат.путь in кандидаты: raise НеполныйСнимок('повтор кандидата')
        относительный = PurePosixPath(кандидат.путь)
        if относительный.is_absolute() or '..' in относительный.parts or str(относительный) != кандидат.путь:
            raise НеполныйСнимок('неканонический путь кандидата')
        кандидаты[кандидат.путь] = кандидат
        if наблюдения.get(('узел', str(PurePosixPath(снимок.корень) / кандидат.путь))) != кандидат.состояние:
            raise НеполныйСнимок('не наблюдён кандидат')
    тексты = dict(снимок.тексты)
    if len(тексты) != len(снимок.тексты) or set(тексты) != {элемент.путь for элемент in кандидаты.values() if элемент.состояние == ('файл',)}:
        raise НеполныйСнимок('неполное покрытие Markdown-байтов')
    for путь, байты in тексты.items():
        if type(байты) is not bytes or наблюдения.get(('read_bytes', str(PurePosixPath(снимок.корень) / путь))) != байты:
            raise НеполныйСнимок('не удержаны исходные Markdown-байты')
        try: байты.decode('utf-8')
        except UnicodeDecodeError as ошибка: raise НеполныйСнимок('повреждённый UTF-8') from ошибка
    if len(set(снимок.выбранные)) != len(снимок.выбранные) or any(элемент not in кандидаты for элемент in снимок.выбранные):
        raise НеполныйСнимок('неполный выбранный состав')
    настройки = dict(снимок.параметры)
    режим = настройки.get('инвентарь')
    обязательные = {'инвентарь', 'среда', 'кодировка', 'Python'} | ({'корень_git', 'конфигурация_git'} if режим == 'git' else set())
    if режим not in ('git', 'filesystem') or set(настройки) != обязательные or настройки.get('кодировка') != 'utf-8':
        raise НеполныйСнимок('неизвестные параметры')

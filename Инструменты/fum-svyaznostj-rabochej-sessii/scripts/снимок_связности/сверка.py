"""Независимо перечитать наблюдённое; метаданные не доказывают тождество."""
from pathlib import Path
from .модель import НеполныйСнимок, Результат, проверить_модель
from .чтение import Наблюдатель, значение, инвентарь, параметры


def сверить(снимок, результат=None):
    проверить_модель(снимок)
    from . import КОД_ЗАГРУЗКИ
    if снимок.код != КОД_ЗАГРУЗКИ: raise НеполныйСнимок('код отличается от исполненного при загрузке')
    if результат is not None:
        if type(результат) is not Результат or результат.вызов != снимок.вызов or результат.снимок != снимок.sha256:
            raise НеполныйСнимок('свидетельство другого вызова или снимка')
        from .проверка import вычислить
        if результат != вычислить(снимок): raise НеполныйСнимок('изменены ошибки свидетельства')
    корень = Path(снимок.корень)
    if параметры(корень) != снимок.параметры: raise НеполныйСнимок('дрейф параметров')
    новый_инвентарь, байты = инвентарь(корень, Наблюдатель(снимок.корень))
    if новый_инвентарь != снимок.инвентарь or байты != снимок.тексты:
        raise НеполныйСнимок('дрейф полного Markdown-инвентаря или байтов')
    for запись in снимок.наблюдения:
        if значение(запись.операция, запись.путь) != запись.значение:
            raise НеполныйСнимок(f'дрейф наблюдения {запись.операция}: {запись.путь}')
    from .поднабор import КОРЕНЬ
    for путь, байты in снимок.код:
        if (КОРЕНЬ / путь).read_bytes() != байты: raise НеполныйСнимок('дрейф закреплённого кода')
    return True

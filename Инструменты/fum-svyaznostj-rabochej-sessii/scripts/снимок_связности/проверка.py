"""Вычисление только над неизменяемым входом, без живых читателей."""
from .модель import Результат, проверить_модель
from .поднабор import пространство
from .пути import Путь, повтор


def вычислить(снимок):
    проверить_модель(снимок)
    чтение = повтор(снимок.наблюдения)
    путь = lambda элемент: Путь(элемент, чтение)
    функции = пространство(путь, снимок.код)
    ошибки = функции['validate_markdown_links'](
        {путь(снимок.корень) / элемент for элемент in снимок.выбранные}, путь(снимок.корень))
    return Результат(снимок.вызов, снимок.sha256, tuple(ошибки))


def проверить(снимок):
    return вычислить(снимок).ошибки

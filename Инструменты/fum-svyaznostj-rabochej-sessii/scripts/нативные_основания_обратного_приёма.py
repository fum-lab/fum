"""Чтение выбранных нативных оснований; без Git, процессов и разрешения записи."""
import историческая_квитанция as к
from происхождение_сообщений import классифицировать_сообщение

ПРЕДЕЛ = 16 * 1024 * 1024
СХЕМА_РЕШЕНИЯ = "fum.решение-ревью-обратного-приёма.1"
ОГРАДА = "```" + СХЕМА_РЕШЕНИЯ + "\n"


def _место(место):
    к.поля(место, {"начало", "конец", "sha256"})
    начало, конец = к.число(место["начало"]), к.число(место["конец"])
    к.требовать(0 < конец - начало <= ПРЕДЕЛ, "Неверный предел диапазона")
    к.sha256(место["sha256"])
    return конец - начало


def _источник(источник):
    к.поля(источник, {"путь", "мета"})
    к.строка(источник["путь"])
    _место(источник["мета"])
    к.требовать(источник["мета"]["начало"] == 0, "Мета должна начинаться с нуля")


def _выбор(байты, отпечаток):
    к.требовать(type(байты) is bytes and len(байты) <= ПРЕДЕЛ, "Неверный вход")
    к.sha256(отпечаток)
    к.требовать(к.хэш(байты) == отпечаток, "Изменён выбранный вход")
    д = к.разобрать(байты)
    к.поля(д, {"схема", "координатор", "поручение", "ревью"})
    к.требовать(д["схема"] == "fum.выбор-нативных-оснований.1", "Неизвестная схема")
    к.идентичность(д["координатор"])
    п, р = д["поручение"], д["ревью"]
    к.поля(п, {"источник", "сообщение"})
    к.поля(р, {"источник", "исполнитель", "интервал", "сообщение", "контекст", "решение_sha256"})
    к.идентичность(р["исполнитель"])
    for часть in (п, р):
        _источник(часть["источник"])
        _место(часть["сообщение"])
        к.требовать(часть["источник"]["мета"]["конец"] <= часть["сообщение"]["начало"],
                    "Сообщение пересекает мета")
    _место(р["интервал"])
    к.требовать(р["источник"]["мета"]["конец"] <= р["интервал"]["начало"]
                < р["сообщение"]["начало"] < р["сообщение"]["конец"] == р["интервал"]["конец"],
                "Неверный порядок контекста и ревью")
    к.поля(р["контекст"], {"turn_id", "cwd", "model", "effort"})
    к.идентичность(р["контекст"]["turn_id"])
    for имя in ("cwd", "model", "effort"):
        к.строка(р["контекст"][имя])
    к.sha256(р["решение_sha256"])
    размеры = [п["источник"]["мета"], п["сообщение"], р["источник"]["мета"], р["интервал"]]
    # Каждый выбранный диапазон и обе предшествующие LF читаются дважды.
    к.требовать(2 * (sum(м["конец"] - м["начало"] for м in размеры) + 2) <= ПРЕДЕЛ,
                "Превышен общий предел чтения")
    return д


def _взять(снимки, источник, место):
    начало, конец = место["начало"], место["конец"]
    данные = снимки.читать(источник["путь"], префикс=конец - начало,
                         начало=начало, предел=ПРЕДЕЛ, приватный=True)
    к.требовать(данные.endswith(b"\n") and к.хэш(данные) == место["sha256"],
                "Повреждённый диапазон нативного источника")
    if начало:
        предыдущий = снимки.читать(источник["путь"], префикс=1, начало=начало - 1, приватный=True)
        к.требовать(предыдущий == b"\n", "Диапазон начинается внутри строки")
    return данные


def _рамка(сырые, тип):
    к.требовать(сырые.endswith(b"\n") and сырые.count(b"\n") == 1, "Нужна одна полная строка")
    запись = к.разобрать_нативный(сырые)
    к.требовать(type(запись) is dict and запись.get("type") == тип
                and type(запись.get("payload")) is dict, "Неверный вид нативной записи")
    return запись["payload"]


def _мета(снимки, источник, исполнитель):
    данные = _взять(снимки, источник, источник["мета"])
    к.требовать(_рамка(данные, "session_meta").get("id") == исполнитель, "Чужой UUID источника")


def _решение(ответ, ожидаемый_sha256, координатор):
    к.требовать(ответ.get("type") == "message" and ответ.get("role") == "assistant"
                and ответ.get("phase") == "commentary", "Нужно видимое commentary модели")
    части = ответ.get("content")
    к.требовать(type(части) is list and len(части) == 1 and type(части[0]) is dict
                and части[0].get("type") == "output_text", "Нужна одна текстовая часть ревью")
    текст = к.строка(части[0].get("text"))
    к.требовать("\r" not in текст, "Нужны буквальные переводы строк LF")
    строки = текст.split("\n")
    начала = [и for и, строка in enumerate(строки) if строка + "\n" == ОГРАДА]
    к.требовать(len(начала) == 1, "Нужна одна именованная ограда")
    начало = начала[0] + 1
    конец = next((и for и in range(начало, len(строки)) if строки[и] == "```"), None)
    к.требовать(конец is not None, "Ограда не закрыта")
    тело = ("\n".join(строки[начало:конец]) + "\n").encode("utf-8")
    к.требовать(тело.endswith(b"\n") and к.хэш(тело) == ожидаемый_sha256,
                "Изменены точные байты решения")
    решение = к.разобрать(тело)
    к.требовать(type(решение) is dict and решение.get("схема") == СХЕМА_РЕШЕНИЯ
                and решение.get("координатор") == координатор, "Чужое решение ревью")
    return тело


def _происхождение_ответа(сырые, ход):
    запись = к.разобрать_нативный(сырые)
    ответ = _рамка(сырые, "response_item")
    происхождение = ответ.get("internal_chat_message_metadata_passthrough")
    к.требовать(type(происхождение) is dict and происхождение.get("turn_id") == ход,
                "Не подтверждён ход ответа модели")
    if "metadata" in запись:
        мета = запись["metadata"]
        к.требовать(type(мета) is dict, "Неверная metadata ответа")
        if "client_authored" in мета:
            к.требовать(мета["client_authored"] is False, "Клиентский ответ не является ревью модели")
    return ответ


def прочитать(выбор_байты, ожидаемый_sha256):
    """Вернуть исходные байты и контекст. Смысл поручения и качество ревью проверяет ROOT."""
    д = _выбор(выбор_байты, ожидаемый_sha256)
    п, р = д["поручение"], д["ревью"]
    снимки = к.Снимки()
    try:
        _мета(снимки, п["источник"], д["координатор"])
        поручение = _взять(снимки, п["источник"], п["сообщение"])
        к.требовать(классифицировать_сообщение(_рамка(поручение, "response_item")) == "человек",
                    "Нет полной runtime-аннотации поручения человека")
        _мета(снимки, р["источник"], р["исполнитель"])
        интервал = _взять(снимки, р["источник"], р["интервал"])
        строки = интервал.split(b"\n")
        к.требовать(строки[-1] == b"" and len(строки) <= 131073, "Неверный интервал строк")
        контекст = _рамка(строки[0] + b"\n", "turn_context")
        к.требовать(all(контекст.get(ключ) == значение for ключ, значение in р["контекст"].items()),
                    "Другой контекст модели")
        позиция = р["интервал"]["начало"] + len(строки[0]) + 1
        выбранное = None
        for строка in строки[1:-1]:
            сырые = строка + b"\n"
            запись = к.разобрать_нативный(сырые)
            к.требовать(type(запись) is dict and type(запись.get("type")) is str
                        and type(запись.get("payload")) is dict, "Неверная рамка интервала")
            к.требовать(запись["type"] not in {"turn_context", "session_meta"},
                        "Промежуточный контекст модели или мета сессии")
            конец = позиция + len(сырые)
            if позиция == р["сообщение"]["начало"]:
                к.требовать(конец == р["сообщение"]["конец"]
                            and к.хэш(сырые) == р["сообщение"]["sha256"],
                            "Подменён выбранный ответ")
                выбранное = сырые
            позиция = конец
        к.требовать(выбранное is not None, "Ответ не совпал с полной строкой интервала")
        ответ = _происхождение_ответа(выбранное, р["контекст"]["turn_id"])
        решение = _решение(ответ, р["решение_sha256"], д["координатор"])
        результат = {"схема": "fum.прочитанные-нативные-основания.1",
            "координатор": д["координатор"], "исполнитель": р["исполнитель"],
            "контекст": dict(р["контекст"]), "поручение_байты": поручение,
            "ревью_событие_байты": выбранное, "ревью_байты": решение, "разрешение_записи": False}
    finally:
        снимки.закрыть()
    результат["прочитано_байт"] = снимки.прочитано
    return результат


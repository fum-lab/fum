"""Читающая композиция .6: первоначальный T, документ A и независимый ACT2."""
import hashlib
from pathlib import Path

import цели_ветки_состояния_узла as цели
import полномочия_ветки_состояния_узла as полномочия


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def поля(значение, ожидаемые):
    требовать(type(значение) is dict and set(значение) == ожидаемые, 'неверные поля генератора состояния')


def проверить_решение(решение):
    поля(решение, {'схема', 'координатор', 'модель', 'усилие', 'постановка', 'поручение',
        'акт', 'подготовка', 'зависимости', 'координация', 'полномочия_узла'})
    требовать(решение['схема'] == 'fum.смысл-дочернего-поручения.4', 'нужна семантика состояния .4')
    требовать(решение['акт']['ветка'] == полномочия.ВЕТКА, 'генератор состояния требует точный state ref')


def расчёт_исполнителя(корень, вход, решение):
    """Пара уже входит в launch-C; создавать пустой J здесь нельзя."""
    import подготовка_дочернего_поручения as генератор
    р = решение['подготовка']['исполнитель']
    поля(р, {'журнал', 'заголовок', 'описание', 'роль', 'цели', 'время', 'проверки', 'наполнение', 'предел_секунд'})
    требовать(type(р['проверки']) is list and bool(р['проверки']), 'нужны непустые будущие проверки')
    for проверка in р['проверки']:
        требовать(type(проверка) is dict and set(проверка) == {'название', 'наборы'},
            'проверки не принимают ручной UUID, порядок или неизвестные поля')
        требовать(type(проверка['название']) is str and bool(проверка['название'].strip())
            and type(проверка['наборы']) is list and len(проверка['наборы']) == 1, 'неверная будущая проверка')
        набор = проверка['наборы'][0]
        требовать(type(набор) is dict and set(набор) == {'каталог', 'шаблон'}, 'неверный набор проверки')
        цели.путь(набор['каталог'])
        требовать(type(набор['шаблон']) is str and набор['шаблон'].startswith('test_')
            and набор['шаблон'].endswith('.py') and not any(з in набор['шаблон'] for з in '/\\\x00\r\n'),
            'неверный шаблон проверки')
    папка = 'Журнал/' + р['журнал']
    ребёнок = Path(вход['исполнитель']['корень'])
    C = вход['постановка']['коммит']
    for имя in ('запрос.md', 'отчёт.md'):
        относительный = папка + '/' + имя
        генератор.обычное.путь(ребёнок, относительный)
        данные = полномочия.гит.объект_файла(корень, C, относительный)
        требовать((ребёнок / относительный).read_bytes() == данные,
            'дочерняя пара должна быть подготовлена и закреплена в launch-C')
    команды = генератор.этап.корневые_команды({'корень': str(корень), 'источники': вход['источники']})
    запрос = (Path(папка) / 'запрос.md').as_posix()
    генератор.этап.коммит.сверить_тексты({'корень': str(ребёнок), 'запрос': запрос}, команды)
    _, записи = генератор.этап.история(ребёнок, запрос)
    прежние = [ф.relative_to(ребёнок).as_posix() for ф, _, _ in записи]
    for ф, _, сырые in записи:
        требовать(полномочия.гит.объект_файла(корень, C, ф.relative_to(ребёнок).as_posix()) == сырые,
            'прежний RAW не закреплён в launch-C')
    номер = max((з['порядок'] for _, з, _ in записи), default=0) + 1
    расчёт = цели.вывести_цели_состояния(координатор=решение['координатор'],
        sha256_постановки=вход['постановка']['sha256'], журнал=р['журнал'],
        первый_номер=номер, роль='исполнитель', число_проверок=len(р['проверки']),
        цели=р['цели'], прежние_записи=прежние)
    требовать(расчёт['цели'] == решение['акт']['область'], 'первоначальный T отличается от рассмотренной области')
    return расчёт


def построить_полномочия(корень, вход, решение, нативный):
    """Проект A; его коммит и контрольный ref создаются отдельным действием ROOT."""
    import подготовка_дочернего_поручения as генератор
    поля(вход['узел'], {'узел', 'репозиторий', 'поколение_полномочий', 'путь', 'контрольная_ветка'})
    узел = вход['узел']
    for имя in ('узел', 'репозиторий', 'поколение_полномочий'):
        полномочия.строка(узел[имя])
    генератор.обычное.путь(корень, узел['путь'])
    требовать(type(узел['контрольная_ветка']) is str
        and узел['контрольная_ветка'].startswith('refs/heads/codex/'), 'нужен отдельный контрольный ref')
    генератор.гит(корень, 'check-ref-format', узел['контрольная_ветка'])
    расчёт = расчёт_исполнителя(корень, вход, решение)
    ребёнок = Path(вход['исполнитель']['корень'])
    H = генератор.гит(ребёнок, 'rev-parse', 'HEAD')
    полномочия.гит.полный_объект(корень, H)
    требовать(полномочия.гит.предок(корень, вход['постановка']['коммит'], H), 'база ребёнка не продолжает C')
    expected = [э for э in расчёт['цели'] if not э.startswith(('Журнал/', 'Индексы/'))]
    требовать(len(expected) == 1, 'нужен один expected')
    return {'схема': полномочия.СХЕМА, 'ветка': полномочия.ВЕТКА,
        'узел': узел['узел'], 'репозиторий': узел['репозиторий'],
        'координатор': решение['координатор'], 'владелец': нативный['исполнитель'],
        'поколение_полномочий': узел['поколение_полномочий'],
        'хэш_корня': hashlib.sha256(str(ребёнок).encode()).hexdigest(),
        'начальный_коммит': вход['постановка']['коммит'], 'исходный_коммит': H,
        'путь': expected[0], 'цели': расчёт['цели'], 'контрольная_ветка': узел['контрольная_ветка']}


def проверить_закреплённые(корень, вход, решение, нативный, *, выбранные=None):
    расчёт = расчёт_исполнителя(корень, вход, решение)
    if вход['фаза'] == 'входы':
        требовать(выбранные is not None and решение['полномочия_узла'] == выбранные,
            'копия полномочий отличается от независимого ACT2')
        источник = выбранные
    else:
        требовать(выбранные is None, 'ROOT не принимает будущий ACT2')
        источник = решение['полномочия_узла']
    A = полномочия.прочитать(корень, источник)
    требовать(A['координатор'] == решение['координатор'] and A['владелец'] == нативный['исполнитель']
        and A['начальный_коммит'] == вход['постановка']['коммит'] and A['цели'] == расчёт['цели']
        and A['хэш_корня'] == hashlib.sha256(вход['исполнитель']['корень'].encode()).hexdigest(),
        'закреплённые полномочия отличаются от native и первоначального T')
    return расчёт

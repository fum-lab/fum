"""Закреплённый план первого ready для уже открытой ROOT .5 подготовки.

Планирование не пишет. Состав меняет штатный updater; исторические отчёты,
модель и v4 защищены. Сверки обнаруживают дрейф, но не атомарны с Git.
"""
import copy
import os
from pathlib import Path
import stat
import uuid

import повторная_подготовка_этапа as повтор
import обновить_состав_карточки as состав

фасад = повтор.фасад
коммит = повтор.коммит
требовать = повтор.требовать
байты = повтор.байты
хэш = повтор.хэш
ПОЛЯ = {'схема', 'прежняя_подготовка', 'прежний_вход', 'прежний_план',
    'новые_выходы', 'новые_проверки', 'новая_связность', 'новый_состав',
    'наполнение', 'составы', 'закрепления'}


def отпечаток(файл):
    с = файл.lstat()
    требовать(stat.S_ISREG(с.st_mode), 'ожидался обычный закреплённый файл')
    return {'sha256': хэш(файл.read_bytes()), 'режим': stat.S_IMODE(с.st_mode)}


def смысл_состава(план):
    # Git-status меняется после применения первого состава; остальные поля
    # штатного плана и код должны совпасть с независимо выбранным рендером.
    return {к: з for к, з in план.items() if к != 'состояние_git'}


def построить_план(вход):
    требовать(type(вход) is dict and set(вход) == ПОЛЯ
        and вход['схема'] == 'fum.продолжение-открытой-подготовки-ROOT.1', 'неверный открытый ROOT вход')
    фп, подготовка = повтор.выбранный(вход['прежняя_подготовка'])
    требовать(type(подготовка) is dict and set(подготовка) == повтор.ПОЛЯ_ПОДГОТОВКИ
        and подготовка['схема'] == 'fum.подготовленный-коммит.7', 'нужна прежняя ROOT .7 подготовка')
    п = подготовка['параметры']
    требовать(type(п) is dict and set(п) == коммит.ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ
        and п['схема'] == 'fum.создание-коммита.5' and п['режим'] == 'контрольная-точка', 'нужна ROOT .5')
    корень = фасад.адреса.проверить_пути(п)
    фасад.проверить_корневой_контур(п, корень, п['родители'] == [п['исходный_коммит']])
    готовность = коммит.готовность.путь_этапа(п)
    требовать(подготовка['готовность'] == str(готовность), 'чужое назначение ready')
    требовать(not os.path.lexists(готовность) and not os.path.lexists(п['квитанция']), 'ready либо квитанция уже существуют')
    фасад.история(корень, п['запрос'])
    полный = готовность.with_name(готовность.stem + '.продолжение-открытого.json')
    фасад.приватный(полный, существует=False)
    требовать(not os.path.lexists(полный), 'занят результат эпизода; повтор эффекта запрещён')
    фв, старый = повтор.выбранный(вход['прежний_вход'])
    фл, прежний = повтор.выбранный(вход['прежний_план'], режим=0o400)
    требовать(type(старый) is dict and старый.get('повтор') is False and 'начало' in старый
        and прежний['вход_sha256'] == хэш(байты(старый)), 'не связан прежний фасад')
    старые_п = фасад.приватный(старый['вход_коммита'])
    требовать(фасад.прочитать(старые_п) == п
        and отпечаток(старые_п) == прежний['снимок']['файлы'][str(старые_п)]
        and п['подготовка'] == str(фп) and подготовка['команды'] == прежний['команды'], 'подменена связь прежней подготовки')
    вид = повтор.контур(п, старый, прежний)
    старое_нап = фасад.приватный(старый['наполнение'])
    нап_до = фасад.прочитать(старое_нап)
    разрешение_до = фасад.приватный(нап_до['разрешение']['путь'])
    требовать(отпечаток(старое_нап) == прежний['снимок']['файлы'][str(старое_нап)]
        and нап_до['задача'] == п['задача'] and нап_до['запрос'] == п['запрос']
        and фасад.прочитать(разрешение_до) == п['разрешённые_цели']
        and хэш(разрешение_до.read_bytes()) == нап_до['разрешение']['sha256'], 'дрейф прежнего наполнения')
    старые = повтор.манифест(корень, п['запрос'])
    требовать(старые, 'нужна фактическая терминальная история v4')
    _, записи = фасад.история(корень, п['запрос'])
    рецепты = {э['идентификатор']: э for э in [*старый['проверки'], старый['связность']]}
    for _, з, _ in записи:
        рецепт = рецепты.get(з['идентификатор'])
        требовать(рецепт is not None and рецепт['порядок'] == з['порядок']
            and з['сессия'] == п['запрос'], 'v4 не относится к выбранному прежнему плану')
        if 'название' in рецепт:
            требовать(з['вызов'] == рецепт['название'] and з['профиль_проверки']['класс'] == рецепт['класс'], 'дрейф рецепта v4')
    курсор = фасад.приватный(п['кэш_модели'])
    источник = фасад.приватный(п['источник_модели'])
    история = коммит.охват.точный_путь(корень, п['история_модели'])
    фасад.проверить_назначение_курсора(п, корень)
    модель, _, _ = повтор.наблюдать_сохранённую(п, коммит.прочитать, коммит.наблюдать_модель)
    наблюдения = коммит.сообщения._разобрать(история.read_bytes())
    требовать(хэш(история.read_bytes()) == подготовка['история_sha256']
        and наблюдения['число_наблюдений'] == подготовка['наблюдений']
        and модель['последнее'] == подготовка['модель']
        and коммит.команды(п) == подготовка['команды'], 'дрейф модели или выбранных команд')
    закрепления = {'HEAD': п['исходный_коммит'], 'ref': п['ветка'], 'родители': п['родители'],
        'v4': старые, 'история_модели': отпечаток(история), 'курсор_модели': отпечаток(курсор),
        'источник_модели': {'путь': str(источник), **отпечаток(источник)}}
    требовать(вход['закрепления'] == закрепления, 'не совпали независимые закрепления')
    фн, наполнение = повтор.выбранный(вход['наполнение'])
    требовать(type(наполнение) is dict and set(наполнение) == {'схема', 'задача', 'запрос', 'разрешение',
        'ожидаемые_цели', 'инструменты', 'профиль', 'поля', 'вставки'}
        and наполнение['схема'] == 'fum.наполнение-карточки.1', 'неверные поля конечного наполнения')
    выходы = вход['новые_выходы']
    требовать(type(выходы) is dict and set(выходы) == повтор.ВЫХОДЫ, 'неполные новые private outputs')
    пути = [фасад.приватный(выходы[к], существует=False, режим=0o400 if к == 'план_наполнения' else 0o600)
        for к in sorted(повтор.ВЫХОДЫ)]
    неизменные = {фп, фв, фл, старые_п, старое_нап, разрешение_до, фн}
    защищаемые = {*неизменные, готовность, полный, курсор, источник, Path(п['сообщение']), Path(п['квитанция'])}
    защищаемые.update(Path(э[к]) for э in п['источники'] for к in ('путь', 'кэш') if к in э)
    проверки = вход['новые_проверки']; связность = вход['новая_связность']
    требовать(type(проверки) is list and len(проверки) == len(старый['проверки'])
        and type(связность) is dict and set(связность) == {'идентификатор', 'порядок'}, 'неполный новый набор проверок')
    номер = max(э['порядок'] for э in старые) + 1
    номера = []; будущие = []
    for н, з in enumerate([*проверки, связность], номер):
        требовать(type(з) is dict and з['порядок'] == н and type(з['порядок']) is int, 'нужен точный max+1')
        и = з['идентификатор']
        требовать(type(и) is str and str(uuid.UUID(и)) == и and и not in номера
            and и not in {э['идентификатор'] for э in старые}, 'повторный либо неверный UUID')
        номера.append(и)
        будущие.append((Path(п['запрос']).parent / 'материалы/запуски-проверок' / f'{н}_{и}.json').as_posix())
        if з is связность: continue
        требовать(set(з) == {'идентификатор', 'порядок', 'название', 'класс', 'аргументы'}
            and type(з['название']) is str and з['название'].strip()
            and з['класс'] in {'адресная', 'полная'}
            and type(з['аргументы']) is list and з['аргументы']
            and all(type(а) is str and а for а in з['аргументы']), 'неверный конечный рецепт')
        требовать((з['класс'] == 'полная') == коммит.отчёты.является_запуском_полной_проверки(корень, з['аргументы']), 'класс не совпал с argv')
    цели = вход['новый_состав']
    требовать(type(цели) is list and цели and all(type(ц) is str for ц in цели)
        and len(set(цели)) == len(цели) and set(будущие) <= set(цели), 'неверный точный T')
    фактические = {э['путь'] for э in старые}
    требовать(фактические <= set(цели), 'старые v4 пропущены в T')
    for ц in п['разрешённые_цели']:
        if ц not in прежний['будущие_цели']:
            требовать(ц in цели, 'не-v4 прежняя цель пропущена')
    for ц in цели:
        файл = коммит.охват.точный_путь(корень, ц)
        требовать(not os.path.lexists(файл) if ц in будущие else файл.is_file(), 'неверная фактическая/future цель')
    _, _, грязные = коммит.охват.прочитать_статус(корень)
    требовать(set(грязные) <= set(цели), 'dirty вне T открытого ROOT')
    требовать(наполнение['задача'] == п['задача'] and наполнение['запрос'] == п['запрос']
        and наполнение['разрешение'] == {'путь': выходы['разрешение'], 'sha256': хэш(байты(цели))}
        and наполнение['ожидаемые_цели'] == будущие, 'не связано конечное наполнение')
    выбранные_составы = вход['составы']
    требовать(type(выбранные_составы) is list and выбранные_составы, 'нужен конечный список составов')
    составы = []; запросы = set()
    отчёты = {корень / ц for ц in цели if Path(ц).name == 'отчёт.md'
        and ц != str(Path(п['запрос']).with_name('отчёт.md'))}
    for з in выбранные_составы:
        требовать(type(з) is dict and set(з) == {'запрос', 'sha256', 'режим', 'разрешение', 'план'}
            and з['запрос'] not in запросы and з['запрос'] in цели, 'неверный либо повторный состав')
        запросы.add(з['запрос'])
        файл = коммит.охват.точный_путь(корень, з['запрос'])
        требовать(отпечаток(файл) == {к: з[к] for к in ('sha256', 'режим')}, 'дрейф выбранного запроса')
        фр, разрешение = повтор.выбранный(з['разрешение']); неизменные.add(фр); защищаемые.add(фр)
        требовать(разрешение['задача'] == п['задача'] and set(разрешение['разрешённые_цели']) <= set(цели), 'состав выходит за T')
        фс = фасад.приватный(з['план'], существует=False, режим=0o400); пути.append(фс)
        план_состава = состав.подготовить(корень, з['запрос'], фр)
        составы.append({'запрос': з['запрос'], 'разрешение': str(фр), 'план': str(фс),
            'смысл': смысл_состава(план_состава)})
        отчёт = файл.with_name('отчёт.md')
        if з['запрос'] != п['запрос']: отчёты.add(отчёт)
    защищаемые |= неизменные
    требовать(len(set(пути)) == len(пути) and not set(пути) & защищаемые
        and not any(os.path.lexists(ф) for ф in пути), 'заняты либо пересечены private роли')
    новое_п = copy.deepcopy(п)
    новое_п.update({к: выходы[к] for к in ('сообщение', 'подготовка', 'квитанция')})
    новое_п['разрешённые_цели'] = цели
    новый_фасад = {'вход_коммита': выходы['вход_коммита'], 'наполнение': выходы['наполнение'],
        'план_наполнения': выходы['план_наполнения'], 'время': старый['время'], 'повтор': True,
        'контур': вид, 'проверки': проверки, 'связность': связность,
        'готовность': {'проверки': номера, 'предел_секунд': старый['готовность']['предел_секунд']}}
    время = фасад.свежесть.parse_display_time(старый['время'])
    требовать(фасад.свежесть.format_msk(время) == старый['время'], 'неканоническое время')
    наблюдаемые = {*неизменные, курсор, источник, история, *отчёты, *(корень / ц for ц in цели)}
    файлы = {str(ф): отпечаток(ф) if os.path.lexists(ф) else None for ф in sorted(наблюдаемые)}
    индекс = Path(фасад.поручения._гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index'))
    слияние = Path(фасад.поручения._гит(корень, 'rev-parse', '--absolute-git-dir')) / 'MERGE_HEAD'
    индекс_sha = хэш(индекс.read_bytes())
    обновления = фасад.план_обновлений({'обновления': ['журнал', 'recency']}, корень, цели, время)
    фасад.проверить_корневой_контур(п, корень, вид == 'обычный')
    требовать(хэш(индекс.read_bytes()) == индекс_sha and повтор.манифест(корень, п['запрос']) == старые
        and all(отпечаток(Path(ф)) == з for ф, з in файлы.items() if з is not None)
        and not os.path.lexists(готовность) and not os.path.lexists(п['квитанция']), 'дрейф в конце планирования')
    return {'схема': 'fum.план-продолжения-открытой-подготовки-ROOT.1', 'вход_sha256': хэш(байты(вход)),
        'контур': вид, 'поколение': -1, 'полный_результат': str(полный), 'замены': {},
        'новый_вход_фасада': выходы['вход_фасада'], 'следующий_номер': номер, 'манифест': старые,
        'неизменные_входы': sorted(map(str, неизменные)), 'неизменные_отчёты': sorted(map(str, отчёты)),
        'исходная_квитанция': п['квитанция'],
        'отсутствующая_готовность': str(готовность), 'составы': составы, 'будущие_цели': будущие,
        'recency_цели': [ц for ц in цели if корень / ц not in отчёты],
        'команды': подготовка['команды'], 'модель': подготовка['модель'],
        'технические_входы': {'коммит': новое_п, 'наполнение': наполнение, 'разрешение': цели, 'фасад': новый_фасад},
        'снимок': {'HEAD': п['исходный_коммит'], 'ref': п['ветка'], 'родители': п['родители'],
            'MERGE_HEAD': хэш(слияние.read_bytes()) if os.path.lexists(слияние) else None,
            'индекс_sha256': индекс_sha, 'файлы': файлы}, 'обновления': обновления}


def предварить_эффект(план):
    п = план['технические_входы']['коммит']; корень = Path(п['корень'])
    фасад.проверить_корневой_контур(п, корень, план['контур'] == 'обычный')
    _, _, грязные = коммит.охват.прочитать_статус(корень)
    требовать(set(грязные) <= set(п['разрешённые_цели']), 'late dirty вне T')
    индекс = Path(фасад.поручения._гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index'))
    требовать(хэш(индекс.read_bytes()) == план['снимок']['индекс_sha256'], 'late дрейф индекса')
    for ф, з in план['снимок']['файлы'].items():
        файл = Path(ф)
        требовать(отпечаток(файл) == з if з is not None else not os.path.lexists(файл), 'late дрейф выбранных байтов')
    требовать(not os.path.lexists(план['отсутствующая_готовность'])
        and not os.path.lexists(п['квитанция'])
        and not os.path.lexists(план['исходная_квитанция']), 'late ready/квитанция')
    слияние = Path(фасад.поручения._гит(корень, 'rev-parse', '--absolute-git-dir')) / 'MERGE_HEAD'
    требовать((хэш(слияние.read_bytes()) if os.path.lexists(слияние) else None)
        == план['снимок']['MERGE_HEAD'] and хэш(индекс.read_bytes()) == план['снимок']['индекс_sha256'], 'late Git дрейф')
    # Адрес проверяется после зависимых файлов, а не только до их чтения.
    фасад.проверить_корневой_контур(п, корень, план['контур'] == 'обычный')


def обновить(корень, выбранный):
    план = состав.подготовить(корень, выбранный['запрос'], Path(выбранный['разрешение']))
    требовать(смысл_состава(план) == выбранный['смысл'], 'дрейф смысла выбранного состава')
    отпечаток_плана = состав.сохранить_план(Path(выбранный['план']), план, корень)
    return состав.применить(корень, выбранный['запрос'], Path(выбранный['разрешение']),
        Path(выбранный['план']), отпечаток_плана)

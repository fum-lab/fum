"""Историческое чтение P.2 без текущего expected/ref, native и установки."""
import time
import повторный_план_журнала_состояния as план


def _сверить(данные, корень, профиль):
    начало = time.monotonic_ns()
    план.требовать(type(данные) is bytes and 0 < len(данные) <= план.читатель.ПРЕДЕЛ, 'неверный размер P.2')
    п = план.читатель.канон.разобрать(данные)
    план.поля(п, план.проверка.ПОЛЯ | {'доверие', 'идентификатор'})
    план.требовать(п['схема'] == 'fum.план-журнала-писателя-состояния.2'
        and п['ветка'] == план.прежний.полномочия.ВЕТКА, 'неизвестный P.2 или ref')
    план.проверка._SHA(п['хэш_корня']); план.проверка._SHA(п['идентификатор'])
    план.требовать(all(п[к] == п['доверие'][к] for к in план.ИД), 'разошлись идентичности P.2 и доверия')
    H = п['исходный_коммит']; план._доверие(корень, п['доверие'], H)
    prefix, label = план.прежний.генератор.разобрать_время(п['время'])
    план.прежний.этап.каркас._проверить_метку_сессии(п['метка'])
    план.требовать(п['журнал'] == prefix+'_'+п['метка']
        and п['заголовок'] == план.прежний.этап.каркас._заголовок_из_метки(п['метка'])
        and п['происхождение_времени'] == 'Получено get-session-time.py --format both: '+prefix+'; '+label+'. Время сохранённого плана.',
        'подмена времени/метки/заголовка')
    план.каркас.контракт.имя_журнала(п['журнал']); план._отсутствие(корень, H, п['журнал'], живой=False)
    for ключ in ('первоначальный_запрос', 'предыдущий_этап'):
        план.прежний._история(корень, п[ключ], H, п['координатор'])
    после_истории = time.monotonic_ns()
    план.проверка._команды(п); план._ресурсы(корень, H, п['строитель'])
    план.требовать(type(п['файлы']) is list and len(п['файлы']) == 2, 'нужна одна пара P.2')
    for файл in п['файлы']:
        план.поля(файл, {'путь', 'текст', 'sha256', 'режим'})
        план.проверка._SHA(файл['sha256'])
        план.требовать(type(файл['текст']) is str and план.хэш(файл['текст'].encode()) == файл['sha256']
            and type(файл['режим']) is int and файл['режим'] == 0o644, 'неверный файл P.2')
    идентификатор, файлы = план.каркас.рассчитать(п)
    план.требовать(п['идентификатор'] == идентификатор and п['файлы'] == файлы,
        'P.2 не совпал с повторным расчётом')
    план._ресурсы(корень, H, п['строитель'])
    if профиль is not None:
        профиль.update({'история_наносекунды': после_истории-начало,
            'повтор_наносекунды': time.monotonic_ns()-после_истории,
            'всего_наносекунды': time.monotonic_ns()-начало, 'API': 0, 'разборов_native': 0})
    return {'документ': п, 'байты': данные, 'sha256': план.хэш(данные), 'разрешение_установки': False}


def сверить(данные, *, корень, профиль=None):
    try: return _сверить(данные, план.гит.физический_корень(корень), профиль)
    except (план.читатель.канон.приём_делегации.гит.ОшибкаОтчёта, план.прежний.этап.каркас.LayoutError,
            KeyError, TypeError, UnicodeError) as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def прочитать(выбор, *, корень, профиль=None):
    try:
        корень = план.гит.физический_корень(корень); план.читатель.канон.источник(выбор)
        данные = план._blob(корень, выбор['коммит'], выбор['путь'])
        план.требовать(план.хэш(данные) == выбор['sha256'], 'подмена raw SHA плана')
        return сверить(данные, корень=корень, профиль=профиль)
    except (план.читатель.канон.приём_делегации.гит.ОшибкаОтчёта, KeyError, TypeError, UnicodeError) as ошибка:
        raise ValueError(str(ошибка)) from ошибка

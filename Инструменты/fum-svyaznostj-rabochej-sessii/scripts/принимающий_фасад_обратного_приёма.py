"""Читающий принимающий стык над native, захватами и чистым планом.

Доверенный принимающий код независимо допускает подлинность, полный охват,
переносимость и действующее поручение. Этот модуль и его план не разрешают
запись сами; kernel получает отдельный callback повторной сверки.
"""
import hashlib
import json
import os
from pathlib import Path

from контракт_обратного_приёма import _ветка, _отпечаток, _поля, _читать, составить_план
import исполнение_обратного_приёма as ядро
from нативные_основания_обратного_приёма import прочитать as прочитать_native
from наблюдение_обратного_приёма import снять_состояние
from проверка_кандидата_обратного_приёма import прочитать as прочитать_проверку


def _байты(данные):
    return (json.dumps(данные, ensure_ascii=False, sort_keys=True,
                       allow_nan=False, indent=2) + "\n").encode()


def _хэш(сырые):
    return hashlib.sha256(сырые).hexdigest()


def _копия(данные):
    сырые = _байты(данные)
    return _читать(сырые, _хэш(сырые), "вход принимающего фасада")


class _Основание:
    def __init__(сам, корень, план, свидетельство, сверка, только_повтор):
        сам._корень = корень
        сам._план = _байты(план)
        сам._свидетельство = свидетельство
        сам._сверка = сверка
        сам._только_повтор = только_повтор

    @property
    def план(сам):
        return json.loads(сам._план)

    @property
    def свидетельство(сам):
        return bytes(сам._свидетельство)

    def сверить(сам):
        # Git-фазу до и после merge независимо проверяет ядро эффекта.
        # Здесь нет HEAD==L, запуска тестов или записи квитанции.
        сам._сверка()

    def _сообщение(сам, сообщение):
        метка = b"FUM-Reverse-Acceptance-SHA256:"
        if (type(сообщение) is not bytes or not сообщение.endswith(b"\n")
                or b"\0" in сообщение or метка in сообщение):
            raise ValueError("Нужно полное исходное сообщение без метки основания")
        сообщение.decode("utf-8")
        return сообщение + b"\n" + метка + b" " + _хэш(сам._свидетельство).encode() + b"\n"

    def применить(сам, каталог, сообщение, автор, коммиттер):
        if сам._только_повтор:
            raise ValueError("Восстановленное основание разрешает только чтение успеха")
        return ядро.применить(сам._корень, сам.план, каталог, сам._сообщение(сообщение),
            автор, коммиттер, сверить_основание=сам.сверить)

    def повтор(сам, каталог, сообщение, автор, коммиттер):
        return ядро.повтор(сам._корень, сам.план, каталог, сам._сообщение(сообщение),
            автор, коммиттер, сверить_основание=сам.сверить)


def подготовить(корень, получатель, источник, выбор_байты, выбор_sha256,
                выбранные_проверки, *, допуск_получателя):
    """Новый допуск: наблюдение настоящего чистого L обязательно."""
    параметры = {"корень": str(корень), "получатель": получатель, "источник": источник,
        "выбор": выбор_байты.decode("utf-8"), "выбор_sha256": выбор_sha256,
        "проверки": выбранные_проверки}
    параметры = _параметры(параметры, допуск_получателя)
    git = снять_состояние(Path(параметры["корень"]), параметры["получатель"], параметры["источник"])
    return _собрать(параметры, git, допуск_получателя, только_повтор=False)


def восстановить(свидетельство, sha256, *, допуск_получателя):
    """Прочитать прежний выбранный успех после перезапуска, без нового эффекта.

    Ожидаемый SHA и callback выбирает доверенная принимающая сторона. Сохранённое
    наблюдение — история L, не доказательство нынешнего HEAD; M проверяет ядро.
    """
    пакет = _читать(свидетельство, sha256, "свидетельство принимающего фасада")
    _поля(пакет, "схема параметры наблюдение план основание", "свидетельство фасада")
    if пакет["схема"] != "fum.свидетельство-принимающего-фасада.1":
        raise ValueError("Неизвестная схема свидетельства фасада")
    параметры = _параметры(пакет["параметры"], допуск_получателя)
    основание = _собрать(параметры, пакет["наблюдение"], допуск_получателя, только_повтор=True)
    if основание.свидетельство != свидетельство:
        raise ValueError("Сохранённое свидетельство отличается от проверенных оснований")
    return основание


def _параметры(параметры, допуск_получателя):
    if not callable(допуск_получателя):
        raise ValueError("Нужен независимый вызываемый допуск получателя")
    параметры = _копия(параметры)
    _поля(параметры, "корень получатель источник выбор выбор_sha256 проверки", "параметры фасада")
    корень = параметры["корень"]
    if type(корень) is not str or not Path(корень).is_absolute() or "\0" in корень:
        raise ValueError("Нужен абсолютный корень")
    if type(параметры["выбор"]) is not str:
        raise ValueError("Нужны исходные UTF-8 байты выбора")
    _отпечаток(параметры["выбор_sha256"], 64, "выбор")
    получатель, источник = параметры["получатель"], параметры["источник"]
    _ветка(получатель, "получатель")
    _ветка(источник, "источник")
    выбранные_проверки = параметры["проверки"]
    if type(выбранные_проверки) is not list or not выбранные_проверки:
        raise ValueError("Нет выбранных проверок")
    for запись in выбранные_проверки:
        _поля(запись, "идентификатор каталог sha256 вход", "выбранная проверка")
        if type(запись["вход"]) is not dict or запись["вход"].get("кандидат") != источник:
            raise ValueError("Выбранная проверка относится к другому кандидату")
    return параметры


def _собрать(параметры, git, допуск_получателя, *, только_повтор):
    корень, получатель, источник = (параметры[ключ] for ключ in ("корень", "получатель", "источник"))
    выбор_байты, выбор_sha256 = параметры["выбор"].encode(), параметры["выбор_sha256"]
    выбранные_проверки = параметры["проверки"]
    git = _копия(git)
    _поля(git, "схема корень_sha256 получатель источник основа_является_предком индекс_sha256 "
          "формат_разницы разница_sha256 разрешение_записи", "наблюдение Git")
    if (git["схема"] != "fum.состояние-git-обратного-приёма.1"
            or git["получатель"] != получатель or git["источник"] != источник
            or git["корень_sha256"] != _хэш(os.fsencode(корень))
            or git["основа_является_предком"] is not True or git["разрешение_записи"] is not False
            or git["формат_разницы"] != "git-raw-z-v1"):
        raise ValueError("Историческое наблюдение не связано с выбранными входами")
    for ключ in ("индекс_sha256", "разница_sha256"):
        _отпечаток(git[ключ], 64, ключ)

    def прочитать():
        native = прочитать_native(выбор_байты, выбор_sha256)
        свидетели, привязки = [], []
        for запись in выбранные_проверки:
            сохранённая = прочитать_проверку(запись["каталог"], запись["sha256"], запись["вход"])
            свидетели.append(_байты({"схема": "fum.свидетельство-переносимой-проверки.1",
                "идентификатор": запись["идентификатор"], "кандидат": источник["коммит"],
                "дерево": источник["дерево"], "статус": "успешно", "код": 0,
                "завершён": True, "зависимости": ["дерево"]}))
            привязки.append({"идентификатор": запись["идентификатор"],
                "результат_sha256": запись["sha256"], "вход": запись["вход"],
                "процесс_sha256": сохранённая["процесс_sha256"],
                "свидетельство_sha256": _хэш(свидетели[-1])})
        return native, свидетели, привязки

    native, свидетели, привязки = прочитать()
    основание = _байты({"схема": "fum.основание-принимающего-фасада.1",
        "координатор": native["координатор"], "получатель": получатель, "источник": источник,
        "разница_sha256": git["разница_sha256"], "корень_sha256": git["корень_sha256"],
        "выбор_sha256": выбор_sha256, "исполнитель_ревью": native["исполнитель"],
        "контекст_ревью": native["контекст"],
        "поручение": native["поручение_байты"].decode(),
        "ревью_событие": native["ревью_событие_байты"].decode(),
        "ревью_sha256": _хэш(native["ревью_байты"]), "проверки": привязки})

    def допустить():
        # Callback ROOT проверяет смысл и независимое происхождение, включая
        # работу по правилам L и отсутствие поздней отмены. JSON-флагом его
        # заменить нельзя. Нормализация зависимостей допускается лишь здесь.
        if допуск_получателя(основание) is not None:
            raise ValueError("Допуск должен завершаться без возвращаемого флага")

    допустить()
    заявка = {"схема": "fum.заявка-обратного-приёма.1", "координатор": native["координатор"],
        "получатель": получатель, "источник": источник,
        "ревью_sha256": _хэш(native["ревью_байты"]),
        "проверки": [{"идентификатор": з["идентификатор"], "sha256": _хэш(с)}
                     for з, с in zip(выбранные_проверки, свидетели, strict=True)]}
    наблюдение = {"схема": "fum.наблюдение-обратного-приёма.1",
        "координатор": native["координатор"], "получатель": получатель, "источник": источник,
        "разница_sha256": git["разница_sha256"], "основа_является_предком": True,
        "рабочее_дерево_чисто": True, "ревью_из_принимающего_дерева": True, "операции_git": []}
    план = составить_план(заявка, наблюдение, native["ревью_байты"], свидетели)
    свидетельство = _байты({"схема": "fum.свидетельство-принимающего-фасада.1",
        "параметры": параметры, "наблюдение": git, "план": план,
        "основание": json.loads(основание)})

    def сверить():
        новые_native, новые_свидетели, новые_привязки = прочитать()
        if (новые_native != native or новые_свидетели != свидетели or новые_привязки != привязки):
            raise ValueError("Изменились выбранные основания приёма")
        допустить()

    сверить()
    return _Основание(корень, план, свидетельство, сверить, только_повтор)

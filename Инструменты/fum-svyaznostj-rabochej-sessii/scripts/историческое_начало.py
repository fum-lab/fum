"""Частная историческая подготовка .8; текущие полномочия остаются у ACT."""
import copy
import os
from pathlib import Path
import stat

import поздняя_привязка_журнала as поздний
import актуальность_приглашения as актуальность

СХЕМА_ВХОДА = 'fum.подготовка-дочернего-поручения.8'
СХЕМА_ПЛАНА = 'fum.план-подготовки-дочернего-поручения.6'
СХЕМА_СВИДЕТЕЛЬСТВА = 'fum.свидетельство-позднего-журнала.3'
требовать = поздний.требовать


def прочитать_частное(имя, режим):
    м = поздний.генератор()
    файл = м.этап.приватный(имя, режим=режим)
    with os.fdopen(os.open(файл, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        метка = поздний.основание.читатель._метка(до)
        требовать(stat.S_ISREG(до.st_mode) and до.st_uid == os.getuid()
            and до.st_nlink == 1 and stat.S_IMODE(до.st_mode) == режим
            and до.st_size <= 128 * 1024 * 1024, 'необычный частный исторический файл')
        сырые = поток.read(128 * 1024 * 1024 + 1)
        требовать(len(сырые) == до.st_size
            and поздний.основание.читатель._метка(os.fstat(поток.fileno()))
                == метка == поздний.основание.читатель._метка(файл.lstat()),
            'частный исторический файл изменился при чтении')
    return сырые, метка


def проверить_план(план):
    м = поздний.генератор()
    м.поля(план, (поздний.ПОЛЯ_НЕЗАВИСИМОГО_ПЛАНА - {'живое_основание'})
        | {'предстартовое_рассмотрение', 'историческое_основание'})
    требовать(план['схема'] == СХЕМА_ПЛАНА and план['фаза'] == 'начало'
        and план['установка'] == [] and план['внешние_действия'] == []
        and план['технические_входы'] is None and план['выбор_акта'] is None
        and план['позднее_решение'] is None, 'историческое начало не разрешает рабочую установку')
    история = план['историческое_основание']
    м.поля(история, {'вход', 'метка', 'контекст', 'исторический_контекст', 'исходный_модуль'})
    требовать(история['вход']['схема'] == СХЕМА_ВХОДА and история['вход']['фаза'] == 'начало'
        and м.хэш(м.байты(история['вход'])) == план['вход_sha256']
        and история['исторический_контекст'] == план['координация']['контекст']
        and план['хэш_координации'] == м.хэш(м.байты(план['координация']))
        and план['свидетельство']['схема'] == СХЕМА_СВИДЕТЕЛЬСТВА,
        'смешаны версии исторического входа, плана или свидетельства')
    старое = история['вход']; свидетельство = план['свидетельство']
    исполнитель = старое['исполнитель']
    м.поля(исполнитель, {'задача', 'корень', 'источник_модели'})
    требовать(старое['писатель'] == исполнитель['задача']
            == свидетельство['исполнитель'] == план['нативная_привязка']['исполнитель']
        and старое['корень'] == исполнитель['корень'] == свидетельство['корень']
        and старое['источник_модели'] == исполнитель['источник_модели']
        and старое['решение'] == свидетельство['решение']
        and старое['постановка'] == свидетельство['постановка']
        and план['снимок']['HEAD'] == старое['постановка']['коммит']
        and план['снимок']['ref'] == свидетельство['ветка'],
        'исторический input8 противоречит native или идентичности свидетельства')
    # Прежний валидатор остаётся строгим; проверяется только читающая проекция.
    проекция = copy.deepcopy(план)
    проекция.pop('историческое_основание')
    проекция['схема'] = поздний.СХЕМА_ПРЕДСТАРТОВОГО_ПЛАНА
    проекция['живое_основание'] = {'контекст': история['контекст']}
    поздний._проверить_независимый_план(проекция)
    return план


def исторический_вид(вход, файл_обзора, хэш_обзора):
    """Внутренний адаптер конечного списка читателей; наружу input7 не выдаётся."""
    м = поздний.генератор()
    требовать(type(вход) is dict and вход.get('схема') == СХЕМА_ВХОДА
        and вход.get('фаза') == 'начало', '.8 допускает только историческое частное начало')
    м.этап.адреса.точный_абсолютный(вход['живой_источник'])
    вид = copy.deepcopy(вход)
    выбор = вид.pop('исторический_источник')
    вид['схема'] = поздний.СХЕМА_НЕЗАВИСИМОГО_ГЕНЕРАТОРА
    поздний._независимый_вход(вид)
    м.поля(выбор, {'путь', 'sha256', 'кэш'})
    # Ремонт раннего отказа P сохраняется и для новой версии: до полного B1.
    решение, _ = поздний._семантика_независимого(Path(вид['корень']), вид['решение'])
    пост, _ = м.источник(Path(вид['корень']), вид['постановка'])
    м.сверить_постановку(решение, вид['постановка'], пост)
    обзор, _ = актуальность.прочитать_выбор(файл_обзора, хэш_обзора)
    контекст = обзор['координация']['контекст']
    файл = м.этап.приватный(выбор['путь'], режим=0o400)
    требовать(str(файл) != вход['живой_источник']
        and выбор['sha256'] == контекст['sha256'], 'B1 не является независимо выбранным историческим снимком')
    with os.fdopen(os.open(файл, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        метка = поздний.основание.читатель._метка(до)
        требовать(stat.S_ISREG(до.st_mode) and до.st_uid == os.getuid()
            and до.st_nlink == 1 and stat.S_IMODE(до.st_mode) == 0o400
            and до.st_size == контекст['граница'], 'неверные тип, режим или EOF исторического B1')
        индекс, _ = поздний.основание.читатель._прочитать_поток(
            поток, обзор['координатор'], None, предел=контекст['граница'])
        требовать(поздний.основание.обработка.контекст_снимка(индекс) == контекст
            and поздний.основание.читатель._метка(os.fstat(поток.fileno()))
                == метка == поздний.основание.читатель._метка(файл.lstat()),
            'исторический B1 подменён или изменился при полном чтении')
    кэш = м.этап.приватный(выбор['кэш'])
    данные = поздний.основание.читатель._кэш_прочитать(кэш, обзор['координатор'])
    требовать(данные is not None and {к: в for к, в in данные.items() if к != 'метка'}
        == {к: в for к, в in индекс.items() if к != 'метка'}, 'кэш исторического B1 подменил полный разбор')
    # Только читающие функции получают этот локальный адаптер. Это НЕ LIVE.
    # B0-команды и их исходный кэш не заменяются расширенным B1.
    вид['живой_источник'] = str(файл)
    return вид, метка


def построить_план(вход, *, выбранный_состав=None, предстартовое_решение=None,
        предстартовый_хэш=None):
    м = поздний.генератор()
    вид, метка = исторический_вид(вход, предстартовое_решение, предстартовый_хэш)
    план = поздний._подготовить_независимое(
        вид, выбранный_состав, предстартовое_решение, предстартовый_хэш)
    живое = план.pop('живое_основание')
    план.update(схема=СХЕМА_ПЛАНА, вход_sha256=м.хэш(м.байты(вход)),
        историческое_основание={'вход': copy.deepcopy(вход), 'метка': метка,
            'контекст': живое['контекст'], 'исторический_контекст': живое['исторический_контекст'],
            'исходный_модуль': str(Path(__file__).resolve())})
    план['свидетельство']['схема'] = СХЕМА_СВИДЕТЕЛЬСТВА
    for имя in (str(Path(__file__).resolve()), вход['исторический_источник']['кэш']):
        файл = м.этап.адреса.точный_абсолютный(имя)
        до = поздний.основание.читатель._метка(файл.lstat())
        сырые = файл.read_bytes()
        требовать(поздний.основание.читатель._метка(файл.lstat()) == до,
            'исторический контур изменился при закреплении')
        план['пины_контура'][имя] = {'метка': до, 'sha256': м.хэш(сырые)}
    файл = Path(вход['исторический_источник']['путь'])
    требовать(поздний.основание.читатель._метка(файл.lstat()) == метка,
        'исторический B1 изменился после проверки плана')
    план['пины_контура'][str(файл)] = {'метка': метка,
        'sha256': вход['исторический_источник']['sha256']}
    return проверить_план(план)


def проверить_историю(вход, план):
    """Reader завершённого .6: исторические данные, без актуального разрешения."""
    проверить_план(план)
    старое = план['историческое_основание']['вход']
    требовать(старое['исполнитель'] == вход['исполнитель']
        and старое['решение'] == вход['решение'] and старое['постановка'] == вход['постановка'],
        'исторический input8 не относится к текущему независимому выбору исполнителя/D/P')
    требовать(вход['живой_источник'] == старое['живой_источник'],
        'ACT заменяет настоящий LIVE исторического начала')
    обзор = план['предстартовое_рассмотрение']
    вид, метка = исторический_вид(старое, обзор['путь'], обзор['sha256'])
    требовать(метка == план['историческое_основание']['метка'], 'подменён адрес исторического B1')
    требовать(поздний._предстартовое(Path(старое['корень']),
        поздний._семантика_независимого(Path(старое['корень']), старое['решение'])[0],
        старое['решение'], старое['постановка'], вид, обзор['путь'], обзор['sha256'],
        история=True) == обзор, 'утрачено рассмотрение исторического начала')
    м = поздний.генератор()
    модуль_плана = план['историческое_основание']['исходный_модуль']
    текущий_читатель = м.этап.адреса.точный_абсолютный(Path(__file__).resolve())
    требовать(м.хэш(текущий_читатель.read_bytes()) == план['пины_контура'][модуль_плана]['sha256'],
        'исполняемый ROOT-reader отличается от закреплённого исторического читателя')
    for имя in (модуль_плана, старое['исторический_источник']['кэш']):
        файл = м.этап.адреса.точный_абсолютный(имя)
        до = поздний.основание.читатель._метка(файл.lstat())
        сырые = файл.read_bytes()
        требовать(план['пины_контура'].get(имя) == {'метка': до, 'sha256': м.хэш(сырые)}
            and поздний.основание.читатель._метка(файл.lstat()) == до,
            'подменён закреплённый исторический читатель или кэш')
    # Фаза, текущий ACT и его новые источники остаются у вызывающего.
    результат = copy.deepcopy(вход)
    результат['живой_источник'] = вид['живой_источник']
    return результат


def применить(вход, файл_плана, ожидаемый_хэш, *, выбранный_состав=None,
        предстартовое_решение=None, предстартовый_хэш=None):
    м = поздний.генератор()
    файл = м.этап.приватный(файл_плана, режим=0o400)
    сырые, _ = прочитать_частное(файл, 0o400)
    требовать(м.хэш(сырые) == ожидаемый_хэш, 'подменён исторический план .6')
    план = проверить_план(м.этап.коммит.сообщения._разобрать(сырые))
    установленные = []
    def граница(остаток=False):
        требовать(построить_план(вход, выбранный_состав=выбранный_состав,
            предстартовое_решение=предстартовое_решение,
            предстартовый_хэш=предстартовый_хэш) == план,
            'дрейф полного исторического плана перед эффектом')
        требовать(прочитать_частное(файл, 0o400)[0] == сырые,
            'immutable исторический план изменился перед эффектом')
        for цель, содержимое, режим, метка in установленные:
            требовать(прочитать_частное(цель, режим) == (содержимое, метка),
                'подменён уже установленный префикс исторического начала')
        if остаток:
            требовать(not any(os.path.lexists(ц) for ц, _, _ in выходы[len(установленные):]),
                'коллизия ещё не установленного исторического выхода')
    каталог = Path(вход['каталог_выходов'])
    намерение = каталог / 'намерение-независимой-привязки.json'
    свидетельство = каталог / 'свидетельство-независимого-журнала.json'
    квитанция = каталог / 'завершённая-независимая-привязка.json'
    данные = м.байты({**план['свидетельство'],
        'план_начала': {'путь': str(файл), 'sha256': ожидаемый_хэш}})
    итог = {'свидетельство': {'путь': str(свидетельство), 'sha256': м.хэш(данные)}, 'повтор': False}
    начало = м.байты({'план_sha256': ожидаемый_хэш, 'вход_sha256': план['вход_sha256']})
    конец = м.байты({'план_sha256': ожидаемый_хэш,
        'вход_sha256': план['вход_sha256'], 'результат': итог})
    выходы = ((намерение, начало, 0o600), (свидетельство, данные, 0o400), (квитанция, конец, 0o600))
    граница()
    if os.path.lexists(квитанция):
        for цель, ожидание, режим in выходы:
            содержимое, метка = прочитать_частное(цель, режим)
            требовать(содержимое == ожидание,
                'историческое завершение или его частный результат подменены')
            установленные.append((цель, содержимое, режим, метка))
        граница()
        return {**итог, 'повтор': True}
    требовать(not any(os.path.lexists(ц) for ц in (намерение, свидетельство)),
        'частичный или неизвестный исход исторического начала; новый эффект запрещён')
    for цель, содержимое, режим in выходы:
        граница(остаток=True)
        поздний._установить(цель, содержимое, режим)
        установленные.append((цель, содержимое, режим, прочитать_частное(цель, режим)[1]))
    граница(остаток=True)
    return итог

"""Служебные события в прежнем контейнере; найденный commit не является прежним ACK."""
import base64
import copy
import hashlib
import json
import time
from uuid import UUID

import компактный_ответ_задачи as компактный
import восстановление_прерванной_задачи as канон

ИДЕНТИЧНОСТЬ = {'узел', 'репозиторий', 'координатор', 'владелец', 'поколение_полномочий'}
ТИП = 'fum-каталог-цикла'
ПРЕДЕЛ = 65536


def кодировать(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False).encode('utf-8')


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def идентификатор(узел, цикл, вид, ключ):
    return 'каталог-' + хэш(кодировать([узел, цикл, вид, ключ]))


def объект(квитанция):
    канон.поля(квитанция, {'описание', 'размер', 'хэш'})
    описание = квитанция['описание']
    канон.поля(описание, {'идентификатор', 'тип', 'версияСхемы', 'источник', 'время', 'спецификация'})
    канон.требовать(type(описание['версияСхемы']) is int and описание['версияСхемы'] == 1, 'неверная версия описания')
    for поле in ('идентификатор', 'тип', 'источник', 'время', 'спецификация'): канон.строка(описание[поле])
    канон.требовать(type(квитанция['размер']) is int and 0 <= квитанция['размер'] <= 64*1024*1024,
        'неверный размер объекта')
    канон.полный_хэш(квитанция['хэш'])
    return {'идентификатор': описание['идентификатор'], 'описание': copy.deepcopy(описание),
        'размер': квитанция['размер'], 'sha256': квитанция['хэш']}


def проверить_байты(ссылка, данные):
    канон.требовать(type(данные) is bytes and len(данные) == ссылка['размер'] and хэш(данные) == ссылка['sha256'],
        'повреждён объект каталога')


def спецификация(описание):
    данные = base64.b64decode(описание['спецификация'], validate=True)
    канон.требовать(len(данные) <= ПРЕДЕЛ, 'превышен предел спецификации')
    return компактный.разобрать(данные)


class Каталог:
    def __init__(сам, контейнер, доверие, поколение):
        сам.контейнер = контейнер
        сам.идентичность = {поле: доверие[поле] for поле in ИДЕНТИЧНОСТЬ}
        сам.поколение = copy.deepcopy(поколение)
        сам.ref = доверие['ref']
        сам.профиль = {имя: 0 for имя in ('перечень_наносекунды', 'извлечение_наносекунды',
            'разбор_наносекунды', 'сериализация_наносекунды', 'служебная_запись_наносекунды', 'извлечено_байтов')}

    def событие(сам, цикл, вид, ключ, время, **поля):
        тело = {'схема': 'fum.событие-каталога-цикла.1', **сам.идентичность, 'цикл': цикл,
            'expected': сам.поколение, 'ref': сам.ref, 'вид': вид, 'ключ': ключ, 'время': время, **поля}
        начало = time.monotonic_ns()
        данные = кодировать(тело)
        канон.требовать(len(данные) <= ПРЕДЕЛ, 'служебная запись превышает предел до чтения')
        описание = {'идентификатор': идентификатор(тело['узел'], цикл, вид, ключ), 'тип': ТИП,
            'версияСхемы': 1, 'источник': 'каталог наблюдений узла', 'время': время,
            'спецификация': base64.b64encode(кодировать({'схема': тело['схема'], 'sha256': хэш(данные)})).decode('ascii')}
        сам.профиль['сериализация_наносекунды'] += time.monotonic_ns()-начало
        return описание, данные

    def сохранить(сам, вход):
        описание, данные = вход
        начало = time.monotonic_ns()
        try:
            ссылка = объект(сам.контейнер.сохранить(copy.deepcopy(описание), данные))
            канон.требовать(ссылка['описание'] == описание, 'подмена описания служебной квитанции')
            проверить_байты(ссылка, данные)
            извлечённое = сам.контейнер.извлечь(ссылка['идентификатор'])
            проверить_байты(ссылка, извлечённое)
            канон.требовать(извлечённое == данные, 'подмена служебного извлечения')
            return ссылка
        finally:
            сам.профиль['служебная_запись_наносекунды'] += time.monotonic_ns()-начало

    def обнаружить(сам):
        try:
            return сам._обнаружить()
        except (KeyError, TypeError, AttributeError, OverflowError) as ошибка:
            raise ValueError("неверная структура каталога") from ошибка

    def _обнаружить(сам):
        начало = time.monotonic_ns()
        перечень = сам.контейнер.перечень()
        канон.поля(перечень, {'схема', 'неполный_хвост', 'записи'})
        канон.требовать(перечень['схема'] == 'fum.перечень-контейнера.1'
            and type(перечень['неполный_хвост']) is bool and type(перечень['записи']) is list
            and len(перечень['записи']) <= 4096, 'неверный перечень контейнера')
        сам.профиль['перечень_наносекунды'] += time.monotonic_ns()-начало
        циклы, записи, история, ссылки = {}, {}, [], {}
        for квитанция in перечень['записи']:
            ссылка = объект(квитанция); описание = ссылка['описание']; имя = ссылка['идентификатор']
            канон.требовать(имя not in записи, 'повтор ID в каталоге')
            записи[имя] = ссылка
            if описание['тип'] not in (ТИП, 'codex-read_thread'): continue
            начало = time.monotonic_ns()
            данные = сам.контейнер.извлечь(имя); проверить_байты(ссылка, данные)
            сам.профиль['извлечение_наносекунды'] += time.monotonic_ns()-начало
            сам.профиль['извлечено_байтов'] += len(данные)
            начало = time.monotonic_ns()
            if описание['тип'] == ТИП:
                канон.требовать(len(данные) <= ПРЕДЕЛ, 'превышен предел служебного события')
                тело = компактный.разобрать(данные)
                вид = тело.get('вид')
                добавки = {'начало': {'адресаты', 'параметры', 'полнота_перечня'},
                    'проверка': {'начало_цикла', 'задача', 'попытка', 'RAW', 'ACK', 'состояние'},
                    'итог': {'начало_цикла', 'номер', 'проверки', 'поколение_актуально'},
                    'ACK-итога': {'начало_цикла', 'номер', 'цель'}}
                канон.требовать(вид in добавки, 'неизвестное событие каталога')
                канон.поля(тело, {'схема', 'цикл', 'expected', 'ref', 'вид', 'ключ', 'время'} | ИДЕНТИЧНОСТЬ | добавки[вид])
                канон.требовать(тело['схема'] == 'fum.событие-каталога-цикла.1'
                    and str(UUID(тело['цикл'])) == тело['цикл']
                    and all(тело[поле] == сам.идентичность[поле] for поле in ИДЕНТИЧНОСТЬ), 'чужая идентичность цикла')
                канон.источник(тело['expected'])
                канон.требовать(тело['ref'] == сам.ref, 'чужой ref цикла')
                канон.требовать(описание == {'идентификатор': идентификатор(тело['узел'], тело['цикл'], вид, тело['ключ']),
                    'тип': ТИП, 'версияСхемы': 1, 'источник': 'каталог наблюдений узла', 'время': тело['время'],
                    'спецификация': base64.b64encode(кодировать({'схема': тело['схема'], 'sha256': хэш(данные)})).decode('ascii')},
                    'подмена описания/ID/SHA события')
                if вид == 'начало':
                    канон.требовать(not any(ключ[0] == тело['цикл'] for ключ in ссылки), 'RAW до начала того же цикла')
                    канон.требовать(тело['цикл'] not in циклы and type(тело['ключ']) is int and тело['ключ'] == 0 and тело['полнота_перечня'] is False,
                        'повтор начала либо недоказанная полнота')
                    канон.требовать(type(тело['адресаты']) is list and type(тело['параметры']) is dict, 'неверные адресаты')
                    адресаты = {}
                    for адресат in тело['адресаты']:
                        канон.поля(адресат, {'задача', 'хост', 'запрос'})
                        канон.идентичность(адресат['задача']); канон.строка(адресат['хост'])
                        канон.требовать(адресат['задача'] not in адресаты and адресат['запрос'] ==
                            {'threadId': адресат['задача'], 'hostId': адресат['хост'], **тело['параметры']}, 'неверный запрос/дубликат адресата')
                        адресаты[адресат['задача']] = адресат
                    циклы[тело['цикл']] = {'начало': тело, 'ссылка': ссылка, 'адресаты': адресаты,
                        'RAW': {}, 'проверки': {}, 'последние': {}, 'итоги': {}, 'ACK-итогов': set()}
                else:
                    канон.требовать(тело['цикл'] in циклы, 'событие до начала')
                    цикл = циклы[тело['цикл']]
                    канон.требовать(тело['начало_цикла'] == цикл['ссылка'] and тело['expected'] == цикл['начало']['expected'],
                        'подмена начала/expected цикла')
                    if вид == 'проверка':
                        задача = тело['задача']; попытка = тело['попытка']
                        канон.требовать(задача in цикл['адресаты'] and type(попытка) is int
                            and попытка == len(цикл['проверки'].get(задача, []))+1 and тело['ключ'] == [задача, попытка], 'неверная попытка')
                        канон.требовать(тело['ACK'] in ('unknown', 'подтверждён') and type(тело['состояние']) is str, 'неверный исход ACK')
                        сырой = тело['RAW']
                        канон.поля(сырой, {'идентификатор', 'описание', 'размер', 'sha256'})
                        канон.требовать(объект({'описание': сырой['описание'], 'размер': сырой['размер'], 'хэш': сырой['sha256']}) == сырой,
                            'подмена ссылки RAW')
                        привязка = спецификация(сырой['описание'])
                        канон.требовать(сырой['описание']['тип'] == 'codex-read_thread'
                            and сырой['идентификатор'] == 'узел-' + хэш(кодировать([тело['узел'], тело['цикл'], задача]))
                            and привязка['цикл'] == тело['цикл'] and привязка['expected'] == тело['expected']
                            and all(привязка[поле] == тело[поле] for поле in ИДЕНТИЧНОСТЬ)
                            and привязка['запрос'] == цикл['адресаты'][задача]['запрос']
                            and привязка['размер'] == сырой['размер'] and привязка['sha256'] == сырой['sha256'],
                            'ACK себя/другого цикла или подмена RAW')
                        if тело['ACK'] == 'подтверждён':
                            канон.требовать(цикл['RAW'].get(задача) == сырой, 'ACK без предшествующего RAW')
                        elif сырой['идентификатор'] in записи:
                            канон.требовать(цикл['RAW'].get(задача) == сырой, 'подмена RAW неизвестного исхода')
                        цикл['проверки'].setdefault(задача, []).append((ссылка, тело))
                        цикл['последние'][задача] = ссылка
                    elif вид == 'итог':
                        номер = тело['номер']
                        канон.требовать(type(номер) is int and номер == len(цикл['итоги'])+1 and тело['ключ'] == номер
                            and type(тело['поколение_актуально']) is bool
                            and all(задача in цикл['последние'] for задача in цикл['адресаты'])
                            and тело['проверки'] == [цикл['последние'].get(задача) for задача in цикл['адресаты']], 'неполный/подменённый итог')
                        цикл['итоги'][номер] = (ссылка, тело)
                    else:
                        номер = тело['номер']
                        канон.требовать(type(номер) is int and номер in цикл['итоги'] and тело['ключ'] == номер
                            and тело['цель'] == цикл['итоги'][номер][0] and номер not in цикл['ACK-итогов'], 'ACK не прежнего итога')
                        цикл['ACK-итогов'].add(номер)
            else:
                тело = спецификация(описание)
                канон.поля(тело, {'схема', 'цикл', 'expected', 'запрос', 'начало', 'конец', 'сериализация', 'размер',
                    'sha256', 'HTTP_байты', 'полнота_истории', 'ошибка_API'} | ИДЕНТИЧНОСТЬ)
                канон.требовать(тело['схема'] == 'fum.описание-чтения-задачи-узла.1'
                    and str(UUID(тело['цикл'])) == тело['цикл']
                    and all(тело[поле] == сам.идентичность[поле] for поле in ИДЕНТИЧНОСТЬ), 'чужая идентичность RAW')
                # Старые RAW до введения lifecycle обнаруживаются как legacy, без восстановленного ACK.
                задача = тело['запрос']['threadId']
                канон.требовать(описание['идентификатор'] == 'узел-' + хэш(кодировать([тело['узел'], тело['цикл'], задача]))
                    and тело['размер'] == ссылка['размер'] and тело['sha256'] == ссылка['sha256']
                    and описание['время'] == тело['конец'], 'подмена описания/SHA RAW')
                if тело['цикл'] in циклы:
                    цикл = циклы[тело['цикл']]
                    канон.требовать(задача in цикл['адресаты'] and задача not in цикл['RAW']
                        and тело['запрос'] == цикл['адресаты'][задача]['запрос']
                        and тело['expected'] == цикл['начало']['expected'], 'чужой цикл/expected/запрос RAW')
                    цикл['RAW'][задача] = ссылка
                ссылки[(тело['цикл'], задача)] = (ссылка, тело)
            сам.профиль['разбор_наносекунды'] += time.monotonic_ns()-начало
        сводка = []
        for UUID_цикла, цикл in циклы.items():
            последний = max(цикл['итоги'], default=0)
            завершён = (последний in цикл['ACK-итогов'] and not перечень['неполный_хвост']
                and цикл['итоги'][последний][1]['проверки'] == [цикл['последние'].get(задача) for задача in цикл['адресаты']])
            сводка.append({'цикл': UUID_цикла, 'начало': цикл['ссылка'], 'итог': 'подтверждён' if завершён else 'unknown',
                'поколение_актуально': цикл['начало']['expected'] == сам.поколение,
                'полнота_перечня': False})
            for задача, адресат in цикл['адресаты'].items():
                сырой = ссылки.pop((UUID_цикла, задача), None)
                проверки = цикл['проверки'].get(задача, [])
                исход = проверки[-1][1] if проверки else None
                история.append({'цикл': UUID_цикла, **адресат, 'объект': None if сырой is None else сырой[0],
                    'ACK_прежнего_процесса': 'unknown' if исход is None else исход['ACK'],
                    'состояние': 'unknown' if исход is None else исход['состояние'],
                    'свежее_в_этом_цикле': False})
        for (UUID_цикла, задача), (сырой, тело) in ссылки.items():
            история.append({'цикл': UUID_цикла, 'задача': задача, 'хост': тело['запрос']['hostId'],
                'запрос': тело['запрос'], 'объект': сырой, 'ACK_прежнего_процесса': 'unknown',
                'состояние': 'legacy RAW без начала/итога', 'свежее_в_этом_цикле': False})
        return {'схема': 'fum.каталог-циклов-наблюдения.1', 'циклы': сводка, 'история': история,
            'неполный_хвост': перечень['неполный_хвост'], 'полнота_перечня': False, 'допуск_эффекта': False}

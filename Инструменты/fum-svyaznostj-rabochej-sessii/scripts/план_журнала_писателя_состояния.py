"""Читающий план нового этапа; установка и допуск здесь отсутствуют."""
import copy
from pathlib import Path
import re
import time

import состояние_задач_узла as читатель
import подготовка_этапа_коммита as этап
import подготовка_дочернего_поручения as генератор
import цели_ветки_состояния_узла as цели
import полномочия_ветки_состояния_узла as полномочия

гит = полномочия.гит
требовать = полномочия.требовать
хэш = полномочия.хэш
СТРОИТЕЛЬ = 'Инструменты/fum-struktura-papok-zaprosov/'


def _состояние(корень):
    индекс = Path(гит.гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index'))
    return (гит.гит(корень, 'rev-parse', 'HEAD'), гит.гит(корень, 'symbolic-ref', 'HEAD'),
        хэш(читатель.прочитать_файл(индекс, предел=читатель.ПРЕДЕЛ)))


def _отсутствие(корень, H, журнал):
    """Только выбранный каталог и его соседи; глобальную цепь не изменяем."""
    родитель = корень/'Журнал'
    требовать(родитель.is_dir() and not родитель.is_symlink(), 'нужен обычный каталог Журнала')
    требовать(not any(п.name.casefold() == журнал.casefold() for п in родитель.iterdir()),
        'новая папка уже существует в checkout или имеет коллизию регистра')
    строки = гит.выполнить(корень, 'ls-tree', '-z', H+':Журнал').stdout.split(b'\0')
    имена = [с.split(b'\t', 1)[1].decode('utf-8') for с in строки if b'\t' in с]
    требовать(not any(имя.casefold() == журнал.casefold() for имя in имена), 'новая папка уже в H')
    ключ = ('Журнал/'+журнал).casefold()
    записи = гит.выполнить(корень, 'ls-files', '-z').stdout.split(b'\0')
    требовать(not any(п and (п.decode('utf-8').casefold() == ключ
        or п.decode('utf-8').casefold().startswith(ключ+'/')) for п in записи),
        'новая папка или её коллизия регистра уже в индексе')


def _история(корень, источник, H, ROOT):
    канон = читатель.канон
    данные = канон.прочитать_источник(корень, источник, {'прочитано_байтов': 0, 'чтений_git_источников': 0})
    путь = цели.путь(источник['путь'])
    требовать(путь.parts[0] == 'Журнал' and путь.name == 'запрос.md', 'нужен исторический запрос')
    требовать(гит.предок(корень, источник['коммит'], H), 'исторический запрос не предок H')
    требовать(re.findall(r'^Codex-Thread-ID: ([^\r\n]+)$', данные.decode('utf-8'), re.M) == [ROOT],
        'исторический запрос принадлежит другому ROOT')


def _построить(вход, *, корень, профиль=None):
    начало = time.monotonic_ns()
    полномочия.поля(вход, {'схема', 'доверие', 'хэш_корня', 'время', 'метка',
        'первоначальный_запрос', 'предыдущий_этап', 'источники'})
    требовать(вход['схема'] == 'fum.вход-плана-журнала-писателя-состояния.1', 'неизвестная схема плана')
    корень = гит.физический_корень(корень)
    требовать(вход['хэш_корня'] == хэш(str(корень).encode()), 'чужой физический корень')
    доверие = copy.deepcopy(вход['доверие'])
    старое = читатель.загрузить_ожидания(доверие, корень=корень)
    ид = {к: старое['ожидания'][к] for к in читатель.ИДЕНТИЧНОСТЬ}
    for ключ in ('координатор', 'владелец'): полномочия.идентификатор(ид[ключ])
    требовать(ид['координатор'] != ид['владелец'], 'ROOT не является своим писателем')
    H = доверие['источник']['коммит']
    до = _состояние(корень)
    требовать(доверие['ref'] == полномочия.ВЕТКА and до[:2] == (H, полномочия.ВЕТКА),
        'нужен точный H принятой ветки состояния')
    после_доверия = time.monotonic_ns()
    требовать(type(вход['время']) is str, 'нужен сохранённый вывод времени')
    prefix, label = генератор.разобрать_время(вход['время'])
    метка = вход['метка']; требовать(type(метка) is str, 'нужна метка новой пары')
    журнал = prefix+'_'+метка
    этап.каркас._validate_stem(журнал, 'новая пара состояния')
    этап.каркас._проверить_метку_сессии(метка)
    заголовок = этап.каркас._заголовок_из_метки(метка)
    _отсутствие(корень, H, журнал)
    for ключ in ('первоначальный_запрос', 'предыдущий_этап'):
        _история(корень, вход[ключ], H, ид['координатор'])
    # Воспроизводимость каркаса связывается с точными исполняемыми байтами builder.
    строитель = []
    for путь, живой in [('scripts/request_folder_layout.py', Path(этап.каркас.__file__)),
            ('шаблоны/запрос.md.шаблон', этап.каркас.КАТАЛОГ_ШАБЛОНОВ/'запрос.md.шаблон'),
            ('шаблоны/отчёт.md.шаблон', этап.каркас.КАТАЛОГ_ШАБЛОНОВ/'отчёт.md.шаблон')]:
        данные = гит.объект_файла(корень, H, СТРОИТЕЛЬ+путь)
        требовать(данные == читатель.прочитать_файл(живой, предел=читатель.ПРЕДЕЛ),
            'строитель или шаблон отличается от H')
        строитель.append({'коммит': H, 'путь': СТРОИТЕЛЬ+путь, 'sha256': хэш(данные)})
    требовать(type(вход['источники']) is list and 1 <= len(вход['источники']) <= 16,
        'нужен конечный список источников команд')
    требовать(all(type(э) is dict and э.get('задача') == ид['координатор']
        and type(э.get('экземпляры')) is list and 1 <= len(э['экземпляры']) <= 128
        for э in вход['источники']), 'команды должны принадлежать ROOT и иметь конечный выбор')
    команды = этап.корневые_команды({'корень': str(корень), 'источники': вход['источники']})
    после_источников = time.monotonic_ns()
    происхождение = 'Получено get-session-time.py --format both: '+prefix+'; '+label+'. Время сохранённого плана.'
    файлы, описание = этап.каркас.подготовить_собственную_пару(корень, журнал, метка, заголовок,
        ид['координатор'], [э['текст'] for э in команды], происхождение_времени=происхождение)
    требовать(len(файлы) == 2 and not описание['idempotent'] and описание['deferred_navigation'],
        'нужны два новых каркаса с отложенной навигацией')
    записи = [{'путь': ф.path.as_posix(), 'текст': ф.data.decode('utf-8'),
        'sha256': хэш(ф.data), 'режим': ф.mode} for ф in файлы]
    требовать([э['путь'] for э in записи] == ['Журнал/'+журнал+'/запрос.md', 'Журнал/'+журнал+'/отчёт.md']
        and all(э['режим'] == 0o644 for э in записи)
        and записи[0]['текст'].count('отложен до передачи координатору') == 2, 'неверная пара builder')
    документ = {'схема': 'fum.план-журнала-писателя-состояния.1', **ид,
        'ветка': полномочия.ВЕТКА, 'исходный_коммит': H, 'хэш_корня': вход['хэш_корня'],
        'журнал': журнал, 'метка': метка, 'заголовок': заголовок, 'время': вход['время'],
        'происхождение_времени': происхождение,
        'первоначальный_запрос': copy.deepcopy(вход['первоначальный_запрос']),
        'предыдущий_этап': copy.deepcopy(вход['предыдущий_этап']), 'команды': команды,
        'источники_команд': [{'задача': э['задача'], 'граница_снимка': copy.deepcopy(э['граница_снимка']),
            'экземпляры': list(э['экземпляры'])} for э in вход['источники']],
        'строитель': строитель, 'файлы': записи}
    данные = читатель.кодировать(документ)
    требовать(len(данные) <= читатель.ПРЕДЕЛ, 'план превышает 64 МиБ')
    _отсутствие(корень, H, журнал)
    требовать(_состояние(корень) == до, 'изменились H, ref или индекс при построении')
    if профиль is not None:
        профиль.update({'доверие_наносекунды': после_доверия-начало,
            'источники_наносекунды': после_источников-после_доверия,
            'каркас_и_повтор_наносекунды': time.monotonic_ns()-после_источников,
            'всего_наносекунды': time.monotonic_ns()-начало, 'команд': len(команды),
            'файлов': len(файлы), 'план_байты': len(данные), 'API': 0})
    return {'байты': данные, 'sha256': хэш(данные), 'разрешение_установки': False}


def построить(вход, *, корень, профиль=None):
    try:
        return _построить(вход, корень=корень, профиль=профиль)
    except (читатель.канон.приём_делегации.гит.ОшибкаОтчёта, этап.каркас.LayoutError) as ошибка:
        raise ValueError(str(ошибка)) from ошибка

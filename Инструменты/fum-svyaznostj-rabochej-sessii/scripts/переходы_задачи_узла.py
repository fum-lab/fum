"""Читающая композиция явно выбранных переходов одной задачи; эффектов нет."""
import argparse
import copy
import json
from pathlib import Path
import sys
import time

import выбор_ожиданий_узла as выбор

канон = выбор.канон
ПРЕДЕЛ_ПЕРЕХОДОВ = 64
ПРЕДЕЛ_УПРАВЛЕНИЯ = 16
ИДЕНТИЧНОСТЬ = ('координатор', 'задача', 'владелец', 'хост')


def _сверить_переход(прежнее, решение):
    if прежнее is None:
        return
    канон.требовать(all(решение[к] == прежнее[к] for к in ИДЕНТИЧНОСТЬ),
        'изменились общие идентичности задачи')
    for эффект, исход in прежнее['эффекты'].items():
        канон.требовать(исход != 'unknown' or решение['эффекты'][эффект] == 'unknown',
            'прежний unknown требует отдельного адресного подтверждения; сброс запрещён')
    тот_же_акт = решение['поручение'] == прежнее['поручение']
    тот_же_этап = решение['этап'] == прежнее['этап']
    канон.требовать(тот_же_акт == тот_же_этап,
        'смена этапа требует нового ACT, новый ACT обозначает новый этап')
    if тот_же_этап:
        канон.требовать(прежнее['состояние'] not in ('закрыт', 'отменён')
            or решение['состояние'] == прежнее['состояние'], 'закрытый этап нельзя открыть заново')
        if прежнее['результат'] is not None:
            канон.требовать(решение['результат'] is not None,
                'готовый результат требует нового ACT для доработки')
            канон.требовать(решение['результат']['источник'] == прежнее['результат']['источник'],
                'смена готового результата требует нового ACT')
            канон.требовать(прежнее['результат']['состояние'] != 'принят'
                or решение['результат']['состояние'] == 'принят', 'принятый результат не понижается')


def _проверить_цепочку(вход, *, корень, профиль=None):
    """Проверяет только объявленный конечный перечень, без поиска пропущенной истории."""
    канон.поля(вход, {'схема', 'доверие', 'постановка_выбора', 'переходы',
        'выбранное', 'позднее_управление'})
    канон.требовать(вход['схема'] == 'fum.цепочка-переходов-задачи-узла.1',
        'неизвестная схема цепочки')
    переходы, управление = вход['переходы'], вход['позднее_управление']
    канон.требовать(type(переходы) is list and 1 <= len(переходы) <= ПРЕДЕЛ_ПЕРЕХОДОВ,
        'нужна конечная непустая цепочка не более 64 переходов')
    канон.требовать(type(управление) is list and len(управление) <= ПРЕДЕЛ_УПРАВЛЕНИЯ,
        'позднее управление ограничено 16 явно выбранными решениями')
    корень = выбор.читатель.доставка_гит.физический_корень(корень)
    выбор.читатель.загрузить_ожидания(вход['доверие'], корень=корень)
    канон.источник(вход['выбранное'])
    канон.требовать(вход['выбранное'] == переходы[-1].get('источник'),
        'выбранное решение не завершает объявленную цепочку')
    измерения = {'прочитано_байтов': 0, 'чтений_git_источников': 0}
    предыдущее, прежнее = None, None
    встреченные = set()
    покинутые_акты = set()
    покинутые_этапы = set()
    for номер, запись in enumerate(переходы + управление):
        канон.поля(запись, {'источник', 'предыдущий', 'основание'})
        канон.источник(запись['источник'])
        канон.требовать(запись['предыдущий'] == предыдущее,
            'перестановка или отсутствующая явная связь предыдущего перехода')
        ключ = tuple(запись['источник'][к] for к in ('коммит', 'путь', 'sha256'))
        канон.требовать(ключ not in встреченные, 'повтор выбранного selector')
        встреченные.add(ключ)
        канон.прочитать_источник(корень, запись['основание'], измерения)
        решение = канон.разобрать(канон.прочитать_источник(корень, запись['источник'], измерения))
        канон.решение_координатора(решение)
        канон.требовать(решение['координатор'] == вход['доверие']['координатор']
            and решение['владелец'] == решение['задача']
            and решение['задача'] != решение['координатор'], 'чужой ROOT или владелец задачи')
        канон.прочитать_поручение(корень, решение['поручение'],
            решение['координатор'], решение['задача'])
        текущий_акт = tuple(решение['поручение'][к] for к in ('коммит', 'путь', 'sha256'))
        if прежнее is not None and решение['поручение'] != прежнее['поручение']:
            покинутые_акты.add(tuple(прежнее['поручение'][к] for к in ('коммит', 'путь', 'sha256')))
            покинутые_этапы.add(прежнее['этап'])
        канон.требовать(текущий_акт not in покинутые_акты, 'возврат к покинутому ACT запрещён')
        канон.требовать(решение['этап'] not in покинутые_этапы, 'покинутый этап нельзя переиспользовать с новым ACT')
        if решение['результат'] is not None:
            канон.прочитать_источник(корень, решение['результат']['источник'], измерения)
        if номер >= len(переходы):
            канон.требовать(решение['состояние'] in ('пауза', 'отменён')
                and прежнее['поручение'] == решение['поручение'],
                'позднее управление должно адресовать выбранный ACT паузой или отменой')
        _сверить_переход(прежнее, решение)
        предыдущее, прежнее = запись['источник'], решение
    if профиль is not None:
        профиль.update(измерения)
    return copy.deepcopy(предыдущее)


def проверить_цепочку(вход, *, корень, профиль=None):
    try:
        return _проверить_цепочку(вход, корень=корень, профиль=профиль)
    except (канон.приём_делегации.гит.ОшибкаОтчёта, KeyError, TypeError) as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def построить(вход, *, корень, профиль=None):
    начало = time.monotonic_ns()
    эффективное = проверить_цепочку(вход, корень=корень, профиль=профиль)
    результат = выбор.построить({'схема': 'fum.выбор-ожиданий-узла.1',
        'доверие': вход['доверие'], 'постановка_выбора': вход['постановка_выбора'],
        'решения': [эффективное]}, корень=корень)
    ожидаемое = канон.разобрать(результат['кандидат'])
    просмотр = канон.предпросмотр(ожидаемое['предпросмотр'], корень=корень,
        каталог_снимков=корень)
    канон.требовать(выбор.читатель.доставка_гит.гит(корень, 'rev-parse', '--verify', вход['доверие']['ref'])
        == вход['доверие']['источник']['коммит'], 'изменилось выбранное поколение после preview')
    if профиль is not None:
        профиль['всего_наносекунды'] = time.monotonic_ns() - начало
    return {'схема': 'fum.прочитанные-переходы-задачи-узла.1',
        'выбранное': copy.deepcopy(вход['выбранное']), 'эффективное': эффективное,
        'кандидат': результат['кандидат'], 'sha256': результат['sha256'],
        'предпросмотр': просмотр, 'допуск_эффекта': False,
        'границы': {'полнота_истории': 'unknown', 'позднее_управление': 'явно выбранные сохранённые решения',
            'runtime': 'unknown', 'незакоммиченная_работа': 'unknown',
            'текущие_наблюдения': 'не запрашивались', 'установка_одно_задачного_перечня': 'запрещена'}}


def главная():
    разбор = argparse.ArgumentParser(allow_abbrev=False, description=__doc__)
    разбор.add_argument('--корень-репозитория', type=Path, required=True)
    разбор.add_argument('--вход', type=Path, required=True)
    аргументы = разбор.parse_args()
    try:
        данные = выбор.читатель.прочитать_файл(аргументы.вход,
            предел=выбор.читатель.ПРЕДЕЛ, приватный=True)
        итог = построить(канон.разобрать(данные), корень=аргументы.корень_репозитория)
        итог['кандидат'] = канон.разобрать(итог['кандидат'])
        sys.stdout.buffer.write(выбор.читатель.кодировать(итог) + b'\n')
        return 0
    except (ValueError, OSError, KeyError, TypeError) as ошибка:
        print(json.dumps({'ошибка': str(ошибка), 'допуск_эффекта': False}, ensure_ascii=False), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(главная())

"""Читающая сверка конечного исторического перечня, без права установки."""
import json
import os
from pathlib import Path
import re
import stat
import subprocess

import контракт_независимого_журнала as контракт


def _oid(значение):
    контракт.требовать(type(значение) is str and re.fullmatch('[0-9a-f]{40}|[0-9a-f]{64}', значение), 'нужен полный коммит')


def _гит(корень, *аргументы):
    среда = {к: з for к, з in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_NO_REPLACE_OBJECTS='1', GIT_OPTIONAL_LOCKS='0', GIT_NO_LAZY_FETCH='1')
    итог = subprocess.run(['git', '--no-optional-locks', '-C', str(корень), *аргументы],
        env=среда, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    контракт.требовать(итог.returncode == 0 and len(итог.stdout) <= 64 * 1024 * 1024,
        'не удалось полностью прочитать выбранный Git-объект')
    return итог.stdout


def _дерево(корень, коммит):
    _oid(коммит)
    контракт.требовать(_гит(корень, 'cat-file', '-t', коммит) == b'commit\n', 'выбран не коммит')
    сырые = _гит(корень, 'ls-tree', '-r', '-t', '-z', '--full-tree', коммит)
    результат = {}
    for строка in сырые.split(b'\0'):
        if not строка:
            continue
        заголовок, имя = строка.split(b'\t', 1)
        режим, тип, oid = заголовок.decode('ascii').split(' ')
        путь = имя.decode('utf-8'); контракт.путь(путь); _oid(oid)
        тип_режима = {'100644': 'blob', '100755': 'blob', '120000': 'blob', '160000': 'commit', '040000': 'tree'}
        контракт.требовать(путь not in результат and тип_режима.get(режим) == тип, 'неоднозначное Git-дерево')
        результат[путь] = (режим, тип, oid)
    return результат, контракт.хэш(сырые)


def _запросы(дерево):
    запросы = {}; имена = set()
    for путь, свойства in дерево.items():
        части = путь.split('/')
        if len(части) != 3 or контракт.ключ_коллизии(части[0]) != контракт.ключ_коллизии('Журнал'):
            continue
        if контракт.ключ_коллизии(части[2]) != контракт.ключ_коллизии('запрос.md'):
            continue
        контракт.требовать(части[0] == 'Журнал' and части[2] == 'запрос.md', 'двойник пути запроса')
        контракт.имя_журнала(части[1], прежнее=True)
        ключ = контракт.ключ_коллизии(части[1])
        контракт.требовать(ключ not in имена and свойства[:2] == ('100644', 'blob'), 'коллизия или неверный тип запроса')
        имена.add(ключ); запросы[путь] = свойства[2]
    return запросы


def _пути(дерево):
    return {контракт.ключ_коллизии(п) for п in дерево}


def _без_отчёта(пути, запрос):
    отчёт = контракт.ключ_коллизии(str(Path(запрос).with_name('отчёт.md')))
    return отчёт not in пути


def _закрытый_json(байты):
    def объект(пары):
        итог = {}
        for к, з in пары:
            контракт.требовать(к not in итог, 'повтор поля манифеста')
            итог[к] = з
        return итог
    try:
        return json.loads(байты, object_pairs_hook=объект)
    except (UnicodeError, json.JSONDecodeError) as ошибка:
        raise ValueError('повреждённый манифест') from ошибка


def _checkout(корень, коммит, записи):
    контракт.требовать(_гит(корень, 'rev-parse', 'HEAD').decode().strip() == коммит, 'HEAD не соответствует выбранному поколению')
    свидетельства = {}
    for запись in записи:
        текущий = корень
        for часть in запись['путь'].split('/'):
            совпадения = [п for п in текущий.iterdir() if контракт.ключ_коллизии(п.name) == контракт.ключ_коллизии(часть)]
            контракт.требовать(len(совпадения) == 1 and совпадения[0].name == часть, 'пропуск или двойник checkout')
            текущий = совпадения[0]; метка = текущий.lstat()
            контракт.требовать(not stat.S_ISLNK(метка.st_mode), 'symlink в историческом пути')
            if часть != 'запрос.md':
                контракт.требовать(stat.S_ISDIR(метка.st_mode), 'нет обычного каталога')
        до = текущий.lstat()
        контракт.требовать(stat.S_ISREG(до.st_mode) and stat.S_IMODE(до.st_mode) == 0o644, 'необычный запрос checkout')
        with os.fdopen(os.open(текущий, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
            данные = поток.read(контракт.ПРЕДЕЛ_ПАРЫ + 1)
            после = os.fstat(поток.fileno())
        контракт.требовать(_метка(до) == _метка(после) == _метка(текущий.lstat())
            and 0 < len(данные) <= контракт.ПРЕДЕЛ_ПАРЫ and контракт.хэш(данные) == запись['sha256'],
            'подмена исторического запроса checkout')
        контракт.требовать(not any(контракт.ключ_коллизии(п.name) == контракт.ключ_коллизии('отчёт.md')
            for п in текущий.parent.iterdir()), 'в checkout существует отчёт или его двойник')
        свидетельства[запись['путь']] = _метка(до)
    return свидетельства


def _метка(метка):
    return (метка.st_dev, метка.st_ino, метка.st_mode, метка.st_size, метка.st_mtime_ns, метка.st_ctime_ns)


def прочитать(корень, манифест, *, ожидаемый_sha256, текущий_коммит, checkout=False):
    контракт.требовать(type(манифест) is bytes and 0 < len(манифест) <= 4 * 1024 * 1024
        and type(checkout) is bool, 'нужны точные байты манифеста и явный режим чтения')
    контракт.отпечаток(ожидаемый_sha256)
    контракт.требовать(контракт.хэш(манифест) == ожидаемый_sha256, 'подмена выбранного манифеста')
    вход = _закрытый_json(манифест)
    контракт.поля(вход, {'схема', 'исходный_коммит', 'записи'})
    контракт.требовать(вход['схема'] == 'fum.исторические-одиночные-запросы-журнала.1', 'неизвестная схема исторического состава')
    _oid(вход['исходный_коммит']); _oid(текущий_коммит)
    записи = вход['записи']
    контракт.требовать(type(записи) is list and 1 <= len(записи) <= 16384, 'пустой или неограниченный исторический перечень')
    пути = set(); ключи = set()
    for запись in записи:
        контракт.поля(запись, {'путь', 'sha256', 'режим'})
        контракт.путь(запись['путь']); контракт.отпечаток(запись['sha256'])
        части = запись['путь'].split('/')
        контракт.требовать(len(части) == 3 and части[0] == 'Журнал' and части[2] == 'запрос.md'
            and re.fullmatch(r'\d{4}-\d{2}-\d{2}_\d{2}-\d{2}-\d{2}_MSK', части[1])
            and type(запись['режим']) is int and запись['режим'] == 0o644, 'неизвестная историческая форма')
        контракт.имя_журнала(части[1], прежнее=True)
        ключ = контракт.ключ_коллизии(запись['путь'])
        контракт.требовать(ключ not in ключи, 'повтор или двойник исторической цели')
        ключи.add(ключ); пути.add(запись['путь'])
    корень = Path(корень).absolute()
    контракт.требовать(корень == корень.resolve() and корень.is_dir()
        and _гит(корень, 'rev-parse', '--show-toplevel').decode().strip() == str(корень), 'нужен физический корень checkout')
    результаты = []
    for коммит in (вход['исходный_коммит'], текущий_коммит):
        дерево, sha = _дерево(корень, коммит); запросы = _запросы(дерево); ключи_дерева = _пути(дерево)
        одиночные = {п for п in запросы if _без_отчёта(ключи_дерева, п)}
        контракт.требовать(одиночные == пути, 'исторический перечень не совпадает с полным Git-поколением')
        for запись in записи:
            данные = _гит(корень, 'cat-file', 'blob', запросы[запись['путь']])
            контракт.требовать(0 < len(данные) <= контракт.ПРЕДЕЛ_ПАРЫ
                and контракт.хэш(данные) == запись['sha256'], 'изменён исторический запрос')
        результаты.append({'коммит': коммит, 'дерево_sha256': sha, 'запросов': len(запросы)})
    if checkout:
        первое = _checkout(корень, текущий_коммит, записи)
        контракт.требовать(первое == _checkout(корень, текущий_коммит, записи), 'checkout изменился во время сверки')
    return {'схема': 'fum.сверка-исторических-одиночных-запросов.1', 'манифест_sha256': ожидаемый_sha256,
        'поколения': результаты, 'запросов': результаты[-1]['запросов'], 'одиночных': sorted(пути),
        'checkout_проверен': checkout, 'разрешение_установки': False}

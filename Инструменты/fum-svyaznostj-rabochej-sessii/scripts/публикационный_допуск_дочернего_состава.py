"""Закрытый публикационный допуск полного конечного stage0-состава обычной .7.

Доказательство живёт в вызове. Готовность связывает его детерминированный SHA;
повторная сверка не переносит допуск на новый, пусть даже чистый, состав.
"""
import contextlib
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import stat
import sys
import types

КОД_ВЫПОЛНЕНИЯ = sys._getframe().f_code
КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
КОРЕНЬ_КОДА = Path(__file__).absolute().parents[3]
ПОЛИТИКА = 'Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/policy.json'
ИСХОДНИКИ_СКАНЕРА = (
    ('path_forms', 'Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/scripts/path_forms.py'),
    ('request_folder_layout', 'Инструменты/fum-struktura-papok-zaprosov/scripts/request_folder_layout.py'),
    ('fum_публикационный_сканер', 'Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/scripts/proveritj-mashinno-lokaljnyiye-puti.py'),
)


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + '\n').encode()


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def разобрать(данные):
    def объект(пары):
        результат = {}
        for ключ, значение in пары:
            требовать(ключ not in результат, 'повтор ключа JSON')
            результат[ключ] = значение
        return результат
    def константа(имя):
        raise ValueError('публикационный допуск: неизвестная константа JSON')
    return json.loads(данные.decode('utf-8'), object_pairs_hook=объект, parse_constant=константа)


def точный_путь(корень, имя):
    части = PurePosixPath(имя).parts
    требовать(части and not имя.startswith('/') and PurePosixPath(имя).as_posix() == имя
        and all(ч not in {'.', '..', ''} for ч in части), 'неканоническая цель')
    текущий = корень
    for н, часть in enumerate(части):
        требовать(часть in {э.name for э in текущий.iterdir()}, 'неточный регистр или отсутствие цели')
        текущий /= часть
        режим = текущий.lstat().st_mode
        требовать(stat.S_ISREG(режим) if н == len(части) - 1 else stat.S_ISDIR(режим),
            'символический или необычный компонент цели')
    return текущий


def требовать(условие, пояснение):
    if not условие:
        raise ValueError('публикационный допуск: ' + пояснение)


def прочитать_код(путь):
    путь = Path(путь).absolute()
    требовать(путь == путь.resolve(), 'символический или неканонический путь кода')
    with os.fdopen(os.open(путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
        до = os.fstat(поток.fileno())
        требовать(stat.S_ISREG(до.st_mode), 'необычный исходник')
        данные = поток.read()
        метка = lambda с: (с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_size, с.st_mtime_ns, с.st_ctime_ns)
        требовать(метка(до) == метка(os.fstat(поток.fileno())) == метка(путь.lstat()),
            'исходник изменился при чтении')
    return данные, stat.S_IMODE(до.st_mode)


def код(создатель):
    пути = {'адаптер': Path(__file__).absolute(), 'создатель': Path(создатель.__file__).absolute(),
        **{имя: КОРЕНЬ_КОДА / путь for имя, путь in ИСХОДНИКИ_СКАНЕРА}}
    сырые = {имя: прочитать_код(путь) for имя, путь in пути.items()}
    требовать(хэш(сырые['адаптер'][0]) == КОД_ПРИ_ЗАГРУЗКЕ
        and compile(сырые['адаптер'][0], __file__, 'exec', dont_inherit=True,
            optimize=sys.flags.optimize) == КОД_ВЫПОЛНЕНИЯ, 'исполняемый адаптер не совпадает с исходником')
    требовать(хэш(сырые['создатель'][0]) == создатель.КОД_ПРИ_ЗАГРУЗКЕ,
        'загруженный создатель не совпадает с исходником')
    исполняемый = getattr(создатель, 'КОД_ВЫПОЛНЕНИЯ', None)
    if исполняемый is not None:
        требовать(compile(сырые['создатель'][0], создатель.__file__, 'exec', dont_inherit=True,
            optimize=sys.flags.optimize) == исполняемый, 'исполняемый создатель не совпадает с исходником')
    return сырые


@contextlib.contextmanager
def сканер(сырые):
    """Исполнить точные проверенные байты, без pyc и прежних модулей сканера."""
    отсутствует = object()
    прежние = {имя: sys.modules.get(имя, отсутствует) for имя, _ in ИСХОДНИКИ_СКАНЕРА}
    прежний_путь = sys.path[:]
    try:
        for имя, относительный in ИСХОДНИКИ_СКАНЕРА:
            путь = КОРЕНЬ_КОДА / относительный
            модуль = types.ModuleType(имя)
            модуль.__file__ = str(путь)
            sys.modules[имя] = модуль
            exec(compile(сырые[имя][0], str(путь), 'exec', dont_inherit=True,
                optimize=sys.flags.optimize), модуль.__dict__)
        yield модуль
    finally:
        sys.path[:] = прежний_путь
        for имя, прежний in прежние.items():
            if прежний is отсутствует:
                sys.modules.pop(имя, None)
            else:
                sys.modules[имя] = прежний


def состав(параметры, создатель):
    корень = Path(параметры['корень'])
    требовать(корень == корень.resolve(), 'нефизический корень состава')
    полный = создатель.индекс(корень)
    алгоритм = создатель.гит(корень, 'rev-parse', '--show-object-format').decode().strip()
    требовать(алгоритм in {'sha1', 'sha256'}, 'неизвестный формат Git-объекта')
    сырые = создатель.гит(корень, 'ls-files', '--stage', '-v', '-z')
    требовать(хэш(сырые) == полный, 'индекс изменился после штатной сверки')
    записи = {}
    for строка in сырые.split(b'\0'):
        if not строка:
            continue
        сведения, имя = строка.split(b'\t', 1)
        флаг, режим, объект, стадия = сведения.decode().split()
        путь = имя.decode('utf-8')
        требовать(флаг == 'H' and стадия == '0' and путь not in записи, 'неоднозначный stage0')
        записи[путь] = (режим, объект)
    цели = параметры['разрешённые_цели']
    требовать(type(цели) is list and цели and len(цели) == len(set(цели)), 'неполный перечень целей')
    журнал = PurePosixPath(параметры['запрос']).parent.as_posix() + '/'
    требовать(all(п in цели for п in записи if п.startswith(журнал)), 'материал своего Журнала вне конечного состава')
    данные = {}; сведения = []
    for путь in dict.fromkeys([*цели, ПОЛИТИКА]):
        требовать(type(путь) is str and путь in записи, 'отсутствующая разрешённая цель: ' + str(путь))
        точный_путь(корень, путь)
        режим, объект = записи[путь]
        требовать(режим in {'100644', '100755'}, 'неподдержанный режим цели: ' + путь)
        содержимое = создатель.гит(корень, 'cat-file', 'blob', объект)
        вычисленный = hashlib.new(алгоритм, b'blob ' + str(len(содержимое)).encode()
            + b'\0' + содержимое).hexdigest()
        требовать(вычисленный == объект, 'прочитанные байты не совпадают с OID blob')
        данные[путь] = содержимое
        сведения.append({'путь': путь, 'режим': режим, 'объект': объект,
            'байты': len(содержимое), 'sha256': хэш(содержимое)})
    требовать(создатель.индекс(корень) == полный, 'состав изменился при чтении blobs')
    return {'корень': str(корень), 'индекс_sha256': полный, 'цели': цели[:], 'входы': сведения}, данные


def сканировать(м, данные, цели, политика):
    """Прежняя оркестрация сканера на точных индексных байтах выбранных целей."""
    полная = м.parse_policy(политика)
    выбранная = м.Policy(tuple(э for э in полная.exceptions if э.path in цели))
    запросы = frozenset(п for п in цели if м._is_request_file(п))
    кандидаты = []; фиксированные = []; тексты = []; инвентарь_ошибочен = False
    for путь in цели:
        содержимое = данные[путь]
        if b'\0' in содержимое:
            категория = ('report.external-source.binary' if м._is_external_source(путь)
                or м._это_бинарное_вложение_запроса(путь, запросы) else 'error.binary-input')
            фиксированные.append(м.Finding(путь, 0, категория))
            инвентарь_ошибочен |= категория.startswith('error.')
            continue
        try:
            текст = содержимое.decode('utf-8')
        except UnicodeDecodeError:
            категория = 'report.external-source.non-utf8' if м._is_external_source(путь) else 'error.non-utf8-input'
            фиксированные.append(м.Finding(путь, 0, категория))
            инвентарь_ошибочен |= категория.startswith('error.')
            continue
        тексты.append((путь, текст))
    исполнители = {}
    for путь, текст in тексты:
        запись = м._каноническая_запись_исполнителя(путь, текст)
        if запись is not None:
            ствол, исполнитель = запись
            исполнители.setdefault(ствол, set()).add(исполнитель)
    for путь, текст in тексты:
        части = PurePosixPath(путь).parts
        ствол = части[1] if len(части) >= 2 and части[0] == 'Журнал' else ''
        кандидаты.extend(м.scan_text(путь, текст, frozenset(исполнители.get(ствол, ()))))
    кандидаты, ошибки_политики, политика_ошибочна = м._apply_policy(кандидаты, выбранная, ПОЛИТИКА)
    находки = tuple(sorted({*фиксированные, *ошибки_политики, *м._deduplicated_findings(кандидаты)}))
    содержание_ошибочно = any(э.category.startswith('error.') for э in находки
        if not э.category.startswith('error.policy-'))
    код = 2 if инвентарь_ошибочен or политика_ошибочна else 1 if содержание_ошибочно else 0
    return {'код': код, 'находки': [{'путь': э.path, 'строка': э.line, 'категория': э.category} for э in находки]}


def построить(параметры, создатель):
    требовать(параметры['схема'] == 'fum.создание-коммита.7', 'необычная дочерняя точка')
    исходники = код(создатель)
    снимок, данные = состав(параметры, создатель)
    политика = разобрать(данные[ПОЛИТИКА])
    with сканер(исходники) as м:
        результат = сканировать(м, данные, снимок['цели'], политика)
    требовать(исходники == код(создатель), 'замыкание кода изменилось при сканировании')
    повтор, повторные_данные = состав(параметры, создатель)
    требовать(повтор == снимок and повторные_данные == данные, 'состав или policy изменились при сканировании')
    требовать(исходники == код(создатель), 'замыкание кода изменилось на последней границе построения')
    требовать(результат['код'] == 0, 'сканер отказал: ' + json.dumps(результат, ensure_ascii=False))
    return {'схема': 'fum.публикационный-допуск-дочернего-состава.1', 'состав': снимок,
        'код': {имя: {'sha256': хэш(д), 'режим': р} for имя, (д, р) in исходники.items()},
        'policy_sha256': хэш(данные[ПОЛИТИКА]), 'результат': результат}


def сверить(допуск, параметры, создатель):
    исходники = код(создатель)
    снимок, данные = состав(параметры, создатель)
    требовать(исходники == код(создатель), 'замыкание кода изменилось при пересверке состава')
    требовать(допуск['схема'] == 'fum.публикационный-допуск-дочернего-состава.1'
        and допуск['результат']['код'] == 0 and снимок == допуск['состав']
        and хэш(данные[ПОЛИТИКА]) == допуск['policy_sha256']
        and {имя: {'sha256': хэш(д), 'режим': р} for имя, (д, р) in исходники.items()} == допуск['код'],
        'прежний допуск не относится к текущему замыканию')


def снимок_готовности(обычный, допуск):
    return {**обычный, 'отпечаток_содержимого': хэш(байты({
        'содержимое': обычный['отпечаток_содержимого'], 'публикация': допуск}))}

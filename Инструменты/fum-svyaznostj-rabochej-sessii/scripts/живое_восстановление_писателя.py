ПРЕДЕЛ = 67108864
ФАЗЫ = ('read1', 'read2', 'send', 'readback')


class ПотокМоста:
    """Фиксированный двусторонний протокол; JSON не выбирает вызываемый код."""
    def __init__(сам, вход=None, выход=None):
        сам.вход = sys.stdin.buffer if вход is None else вход
        сам.выход = sys.stdout.buffer if выход is None else выход
        сам.цикл = str(uuid.uuid4())
        сам.фазы = []
        сам.ожидает_подтверждения = None

    def вывести(сам, значение):
        сам.выход.write(испытание.байты(значение)); сам.выход.flush()

    def вызвать(сам, фаза, параметры):
        канон.требовать(сам.ожидает_подтверждения is None and tuple(сам.фазы) == ФАЗЫ[:len(сам.фазы)]
            and len(сам.фазы) < 4 and ФАЗЫ[len(сам.фазы)] == фаза, 'повтор или перестановка фазы моста')
        сам.фазы.append(фаза)
        контекст = {'цикл':сам.цикл,'фаза':фаза,'задача':параметры['threadId']}
        сам.вывести({'схема':'fum.запрос-живого-восстановления.1',**контекст,'параметры':параметры})
        def кадр():
            строка=сам.вход.readline(65537)
            канон.требовать(len(строка)<=65536 and строка.endswith(b'\n'),'неполный служебный кадр')
            return канон.разобрать(строка)
        заголовок = кадр()
        канон.поля(заголовок,{'схема',*контекст,'байты','sha256'})
        канон.требовать(заголовок['схема']=='fum.передача-ответа-живого-восстановления.1'
            and all(заголовок[к]==з for к,з in контекст.items())
            and type(заголовок['байты']) is int and 0<заголовок['байты']<=ПРЕДЕЛ,'чужой кадр ответа')
        канон.полный_хэш(заголовок['sha256'])
        данные=сам.вход.read(заголовок['байты'])
        канон.требовать(len(данные)==заголовок['байты'] and сам.вход.read(1)==b'\n','неполный ответ моста')
        конец=кадр()
        канон.требовать(конец=={**заголовок,'схема':'fum.конец-ответа-живого-восстановления.1'}
            and канон.хэш(данные)==заголовок['sha256'],'повреждён конец или SHA ответа')
        сам.ожидает_подтверждения={**контекст,'байты':len(данные),'sha256':канон.хэш(данные)}
        return данные

    def подтвердить(сам, объект):
        if сам.ожидает_подтверждения is not None:
            сам.вывести({'схема':'fum.ACK-ответа-живого-восстановления.1',
                **сам.ожидает_подтверждения,'объект':объект})
            сам.ожидает_подтверждения=None


def _файл(путь, предел=2*1024*1024):
    return узел.прочитать_файл(путь,предел=предел,приватный=True)


def _выбор(путь, хэш_выбора, ожидание, *, свежий=True):
    канон.полный_хэш(хэш_выбора)
    данные=_файл(путь)
    канон.требовать(канон.хэш(данные)==хэш_выбора,'изменился независимый выбор ROOT')
    значение=канон.разобрать(данные)
    канон.поля(значение,{'схема','ожидание_sha256','хранилище','нативный','контроль_координатора','начало','конец'})
    канон.требовать(значение['схема']=='fum.выбор-живого-восстановления.1'
        and значение['ожидание_sha256']==канон.хэш(испытание.байты(ожидание)), 'выбор ROOT не связан с ожиданием')
    начало,конец=значение['начало'],значение['конец']
    канон.требовать(type(начало) is int and type(конец) is int and 0<конец-начало<=600,'неверный срок выбора ROOT')
    канон.требовать(not свежий or начало<=time.time()<=конец,'просрочено независимое основание ROOT')
    return значение


def _приватный_каталог(имя, корни):
    путь=канон.физический_путь(имя)
    свойства=путь.stat()
    канон.требовать(stat.S_ISDIR(свойства.st_mode) and свойства.st_uid==os.getuid()
        and свойства.st_mode & 0o077==0,'нужен собственный приватный каталог')
    for корень in корни:
        общий=Path(канон.обычное_поручение._гит(корень,'rev-parse','--path-format=absolute','--git-common-dir')).resolve()
        канон.требовать(not путь.is_relative_to(корень) and not путь.is_relative_to(общий),'данные должны находиться вне checkout и Git')
    return путь


def _контроль_гит(ожидание, корень, выбор):
    контроль=выбор['контроль_координатора']
    канон.поля(контроль,{'корень','ref','HEAD'})
    корневое_дерево=канон.физический_путь(контроль['корень'])
    канон.требовать(корневое_дерево==корень and канон.обычное_поручение._гит(корневое_дерево,'symbolic-ref','HEAD')==контроль['ref']
        and канон.обычное_поручение._гит(корневое_дерево,'rev-parse','HEAD')==контроль['HEAD'], 'изменилось текущее основание ROOT')
    снимок=канон.доставка_план.снимок(Path(ожидание['корень']),ожидание['владелец'],ожидание['ref'])
    канон.требовать(снимок['коммит']==ожидание['HEAD'],'дрейф фактического HEAD/ref')


def _метаданные_нативного_источника(имя):
    путь=канон.физический_путь(Path(имя).parent,Path(имя).name)
    с=путь.stat()
    return [с.st_dev,с.st_ino,с.st_size,с.st_mtime_ns,с.st_ctime_ns]


def _снимок_нативного_источника(имя, предел):
    """Прочитанные bytes и исходная FD identity принимаются только вместе."""
    путь=канон.физический_путь(Path(имя).parent,Path(имя).name)
    дескриптор=os.open(путь,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    метка=lambda с:[с.st_dev,с.st_ino,с.st_size,с.st_mtime_ns,с.st_ctime_ns]
    try:
        до=os.fstat(дескриптор)
        канон.требовать(stat.S_ISREG(до.st_mode) and до.st_nlink==1 and до.st_uid==os.getuid()
            and до.st_mode & 0o077==0 and 0<до.st_size<=предел,'небезопасный native')
        # Канонический bounded reader проверяет байты и собственный FD. Внешний
        # FD закреплён ДО этого чтения, новая метка после него не принимается.
        данные=_файл(путь,предел)
        канон.требовать(метка(os.fstat(дескриптор))==метка(до),'native изменился после чтения bytes')
        текущий=канон.физический_путь(путь.parent,путь.name)
        адрес=os.open(текущий,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
        try:канон.требовать(метка(os.fstat(адрес))==метка(до),'подменён адрес native')
        finally:os.close(адрес)
        канон.требовать(метка(os.fstat(дескриптор))==метка(до),'native изменился при проверке адреса')
        return данные,метка(до)
    finally:os.close(дескриптор)


def _основания(ожидание, корень, выбор, профиль):
    акт=испытание._ожидание(ожидание,корень,профиль)
    _контроль_гит(ожидание,корень,выбор)
    канон.обычное_поручение._гит(Path(ожидание['корень']),'merge-base','--is-ancestor',
        акт['постановка']['коммит'],ожидание['HEAD'])
    решение=канон.разобрать(канон.прочитать_источник(корень,ожидание['решение_координатора'],профиль))
    канон.решение_координатора(решение)
    for имя in ('координатор','задача','хост','владелец','поручение','этап','событие','ход'):
        канон.требовать(решение[имя]==ожидание[имя],'дрейф решения ROOT: '+имя)
    канон.требовать(решение['состояние']=='открыт' and решение['ожидание'] is None
        and решение['результат'] is None and all(з=='не было' for з in решение['эффекты'].values()),
        'пауза, отмена, результат, неизвестность или отсутствие открытого допуска ROOT')
    нативный_источник=выбор['нативный'];канон.поля(нативный_источник,{'путь','размер','sha256'})
    канон.требовать(type(нативный_источник['размер']) is int and 0<нативный_источник['размер']<=256*1024*1024,'неверная граница native')
    данные,метаданные=_снимок_нативного_источника(нативный_источник['путь'],нативный_источник['размер'])
    канон.требовать(len(данные)==нативный_источник['размер'] and канон.хэш(данные)==нативный_источник['sha256'] and данные.endswith(b'\n'),
        'нативное состояние изменилось или неполно')
    начало,контекст,_=канон.обычное_поручение.постановка.прочитать_начало_источника(нативный_источник['путь'])
    поручение=канон.обычное_поручение.постановка.прочитать_нативное_поручение(нативный_источник['путь'])
    канон.требовать(начало.get('id')==ожидание['задача'] and начало.get('cwd')==ожидание['корень']
        and начало.get('thread_source')=='agent_created_thread'
        and начало.get('git',{}).get('commit_hash')==акт['постановка']['коммит']
        and поручение['отправитель']==ожидание['координатор']
        and канон.хэш(поручение['текст'].encode())==акт['хэш_нативного_поручения'], 'native не подтверждает владельца и первоначальный ACT')
    последний=None
    for строка in данные.splitlines():
        запись=канон.разобрать(строка)
        if запись.get('type')=='turn_context': последний=запись.get('payload')
    канон.требовать(type(последний) is dict and последний.get('cwd')==ожидание['корень']
        and последний.get('model')==ожидание['модель'] and последний.get('effort')==ожидание['усилие'],
        'не подтверждены фактические модель/усилие')
    канон.требовать(_снимок_нативного_источника(нативный_источник['путь'],нативный_источник['размер'])==(данные,метаданные),'native изменился при сверке')
    _контроль_гит(ожидание,корень,выбор)
    return {'владелец':начало['id'],'модель':последний['model'],'усилие':последний['effort'],
        'нативный_sha256':нативный_источник['sha256'],'нативный_метаданные':метаданные,'поручение':copy.deepcopy(ожидание['поручение']),
        'поздняя_постановка':copy.deepcopy(ожидание['поздняя_постановка'])}


def _сохранить(контейнер, данные, цикл, фаза, параметры, профиль):
    канон.требовать(type(данные) is bytes and 0<len(данные)<=ПРЕДЕЛ,'нужен полный доступный ответ')
    спецификация={'схема':'fum.полный-ответ-живого-восстановления.1','цикл':цикл,'фаза':фаза,
        'запрос':параметры,'байты':len(данные),'sha256':канон.хэш(данные),'HTTP_байты':'unknown'}
    описание={'идентификатор':'live-'+канон.хэш(испытание.байты([цикл,фаза,параметры['threadId']])),
        'тип':'codex-send_message_to_thread' if фаза=='send' else 'fum-живое-чтение-задачи',
        'версияСхемы':1,'источник':'фиксированный мост официального API','время':узел.время_наблюдения(),
        'спецификация':base64.b64encode(узел.кодировать(спецификация)).decode('ascii')}
    начало=time.monotonic_ns()
    try:
        объект=каталог.объект(контейнер.сохранить(описание,данные))
        канон.требовать(объект['описание']==описание,'подменено описание ответа')
        узел.ЦиклНаблюдения.проверить_объект(объект,данные)
        извлечённое=контейнер.извлечь(объект['идентификатор'])
        узел.ЦиклНаблюдения.проверить_объект(объект,извлечённое)
        канон.требовать(извлечённое==данные,'контейнер вернул другие байты')
        профиль['сохранено_байтов']+=len(данные)
        return объект,извлечённое
    finally:профиль['контейнер_наносекунды']+=time.monotonic_ns()-начало


def _проекция(данные, ожидание, *, исходный):
    проекция=узел.проекция_ответа(данные,задача=ожидание['задача'],хост=ожидание['хост'])
    ход=проекция['текущий_ход'];задача=проекция['задача']
    канон.требовать(проекция['страница']['limit']==1,'нужен адресный latest')
    канон.требовать('cwd' not in задача or задача['cwd']==ожидание['корень'],'дрейф cwd API')
    if исходный:
        канон.требовать(ход is not None and ход['id']==ожидание['ход'] and ход['status']=='interrupted'
            and ход['completedAt']==ожидание['completedAt'] and задача['status']['type']=='idle'
            and not задача['status'].get('activeFlags'),'последний прерванный неактивный ход не подтверждён')
    return проекция


def _ответ_отправки(данные, объект):
    # Это не контракт read_thread и не тестовый ACK. Успех вызова не равен приёмке.
    исход='unknown'
    try:
        ответ=канон.разобрать(данные)
        канон.требовать(type(ответ) is dict and set(ответ)<={'content','isError'}
            and type(ответ.get('content')) is list and len(ответ['content'])>0,'неизвестная оболочка send')
        канон.требовать(type(ответ.get('isError',False)) is bool,'неверный isError send')
        for часть in ответ['content']:
            канон.поля(часть,{'type','text'})
            канон.требовать(часть['type']=='text' and type(часть['text']) is str,'неизвестная часть send')
        исход='ошибка API' if ответ.get('isError',False) else 'ответ API сохранён'
    except (ValueError,TypeError,KeyError,UnicodeError):pass
    return {'схема':'fum.ответ-отправки-живого-восстановления.1','объект':объект,
        'исход':исход,'принятие_команды':'unknown'}


def _прочитать_намерение(путь):
    запись=канон.разобрать(_файл(путь))
    канон.поля(запись,{'схема','цикл','ключ','связь','конверт','состояние','ответ','чтения','доказательства'})
    канон.требовать(запись['схема']=='fum.намерение-живой-отправки.1'
        and запись['связь']==канон.хэш(испытание.байты(запись['конверт']))
        and запись['состояние'] in ('намерение','захват','ответ'),'повреждена или чужая запись намерения')
    канон.требовать((запись['состояние']=='ответ')==(запись['ответ'] is not None),'неполное состояние ответа')
    канон.идентичность(запись['цикл'])
    канон.требовать(type(запись['чтения']) is list and 1<=len(запись['чтения'])<=3,'неверный перечень чтений')
    if запись['ответ'] is not None:
        канон.поля(запись['ответ'],{'схема','объект','исход','принятие_команды'})
        канон.требовать(запись['ответ']['схема']=='fum.ответ-отправки-живого-восстановления.1','чужой ответ')
    return запись



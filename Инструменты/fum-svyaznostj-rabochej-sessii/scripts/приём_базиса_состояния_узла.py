def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def поля(значение, ожидаемые):
    требовать(type(значение) is dict and set(значение) == set(ожидаемые),
        'неверные закрытые поля приёма базиса')


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True,
        separators=(',', ':'), allow_nan=False) + '\n').encode('utf-8')


def разобрать(данные):
    def пары(элементы):
        итог = {}
        for ключ, значение in элементы:
            требовать(ключ not in итог, 'повторный JSON-ключ приёма базиса')
            итог[ключ] = значение
        return итог
    def константа(значение):
        raise ValueError('нечисловая JSON-константа приёма базиса')
    return json.loads(данные.decode('utf-8'), object_pairs_hook=пары,
        parse_constant=константа)


def полный_идентификатор(значение):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{40}', значение),
        'нужен полный OID, а не ref или выражение')
    return значение


def точное_имя(имя):
    требовать(type(имя) is str and bool(имя) and not имя.startswith('/')
        and not any(с in имя for с in ('\\', ':', '\x00'))
        and not any(unicodedata.category(с).startswith('C') for с in имя)
        and all(часть not in ('', '.', '..') and часть.casefold() != '.git'
            for часть in имя.split('/')),
        'небезопасное имя пути базиса')
    требовать(имя == unicodedata.normalize('NFC', имя), 'неканоническое Unicode-имя базиса')
    return имя


def среда_гит():
    # Перенаправление репозитория и lazy fetch не являются входами расчёта.
    результат = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
    результат.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_SYSTEM=os.devnull,
        GIT_CONFIG_GLOBAL=os.devnull, GIT_NO_LAZY_FETCH='1', GIT_TERMINAL_PROMPT='0')
    return результат


def гит(корень, *аргументы, допустимые_коды=(0,)):
    исполняемый = shutil.which('git')
    требовать(исполняемый is not None and Path(исполняемый).is_absolute(), 'нет выбранного Git')
    аргументы_процесса = [исполняемый, '--no-replace-objects', '--no-optional-locks',
        '-c', 'core.hooksPath=' + os.devnull, '-c', 'core.fsmonitor=false',
        '-c', 'core.untrackedCache=false', '-c', 'core.quotePath=false',
        '-c', 'core.fileMode=true', '-c', 'core.pager=cat',
        '-C', str(корень), *аргументы]
    ответ = subprocess.run(аргументы_процесса, env=среда_гит(), capture_output=True, timeout=60)
    требовать(ответ.returncode in допустимые_коды, 'не удалось прочитать Git-объект базиса')
    return ответ.stdout


def корень_гит(корень):
    корень = Path(корень).resolve(strict=True)
    требовать(корень.is_dir(), 'нужен каталог собственного Git-корня')
    фактический = Path(гит(корень, 'rev-parse', '--show-toplevel').decode().strip())
    требовать(фактический.resolve() == корень, 'передан вложенный либо чужой Git-корень')
    требовать(гит(корень, 'rev-parse', '--show-object-format').strip() == b'sha1',
        'контракт требует объявленный SHA1 Git-формат')
    требовать(гит(корень, 'rev-parse', '--is-shallow-repository').strip() == b'false',
        'неполная shallow-история базиса')
    частичная = гит(корень, 'config', '--local', '--get-regexp',
        r'^(extensions\.partialclone|remote\..*\.promisor)$', допустимые_коды=(0, 1))
    требовать(not частичная, 'partial/promisor-история базиса запрещена')
    адрес = гит(корень, 'rev-parse', '--git-path', 'info/grafts').decode().strip()
    путь = Path(адрес)
    if not путь.is_absolute():
        путь = корень / путь
    требовать(not os.path.lexists(путь), 'grafts не являются историей принятого базиса')
    return корень


def объект(корень, объектный_идентификатор, тип):
    полный_идентификатор(объектный_идентификатор)
    данные = гит(корень, 'cat-file', тип, объектный_идентификатор)
    фактический = hashlib.sha1(тип.encode() + b' ' + str(len(данные)).encode()
        + b'\0' + данные).hexdigest()
    требовать(фактический == объектный_идентификатор, 'Git-объект не соответствует сырым байтам')
    return данные


def коммит(корень, объектный_идентификатор):
    заголовок = объект(корень, объектный_идентификатор, 'commit').split(b'\n\n', 1)[0].split(b'\n')
    деревья = [э[5:].decode('ascii') for э in заголовок if э.startswith(b'tree ')]
    родители = [э[7:].decode('ascii') for э in заголовок if э.startswith(b'parent ')]
    требовать(len(деревья) == 1, 'неоднозначное дерево коммита базиса')
    полный_идентификатор(деревья[0])
    for объектный_идентификатор in родители:
        полный_идентификатор(объектный_идентификатор)
    return {'дерево': деревья[0], 'родители': родители}


def таблица(корень, объектный_идентификатор):
    записи = гит(корень, 'ls-tree', '-r', '-z', '--full-tree', объектный_идентификатор)
    требовать(not записи or записи.endswith(b'\0'), 'неполный список дерева базиса')
    итог = {}
    for строка in записи.split(b'\0'):
        if not строка:
            continue
        мета, путь = строка.split(b'\t', 1)
        режим, тип, файловый_объект = мета.decode('ascii').split(' ')
        имя = точное_имя(путь.decode('utf-8'))
        требовать(имя not in итог, 'повторный путь дерева базиса')
        полный_идентификатор(файловый_объект)
        итог[имя] = (режим, тип, файловый_объект)
    return итог


def коллизии(таблицы):
    компоненты = {}
    листья = set().union(*(set(т) for т in таблицы))
    for имя in листья:
        части = имя.split('/')
        for число in range(1, len(части) + 1):
            путь = '/'.join(части[:число])
            ключ = unicodedata.normalize('NFC', путь).casefold()
            прежний = компоненты.setdefault(ключ, путь)
            требовать(прежний == путь, 'Unicode/casefold-коллизия путей базиса')
            if число < len(части):
                требовать(путь not in листья, 'переход файл/каталог в составе базиса')


def изменения(до, после):
    return {п for п in set(до) | set(после) if до.get(п) != после.get(п)}


class ПакетСырыхОбъектов:
    """Один закрываемый Git-процесс; все запрошенные байты хэшируются заново."""
    предел_развёрнутых_записей = 200000
    предел_байтов_путей = 32 * 1024 * 1024

    def __init__(сам, корень):
        исполняемый = shutil.which('git')
        требовать(исполняемый is not None and Path(исполняемый).is_absolute(), 'нет выбранного Git')
        сам.процесс = subprocess.Popen([исполняемый, '--no-replace-objects',
            '--no-optional-locks', '-c', 'core.hooksPath=' + os.devnull,
            '-c', 'core.fsmonitor=false', '-c', 'core.untrackedCache=false',
            '-C', str(корень), 'cat-file', '--batch'], env=среда_гит(),
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        сам.буфер = bytearray()
        сам.срок = time.monotonic() + 120
        сам.байтов = 0
        сам.метаданные = {}
        сам.данные = {}
        сам.развёрнуто = 0
        сам.байтов_путей = 0

    def __enter__(сам):
        return сам

    def __exit__(сам, тип, значение, след):
        ошибка = None
        try:
            try:
                сам.процесс.stdin.close()
            except OSError as сбой:
                ошибка = сбой
            try:
                исход = сам.процесс.wait(timeout=2)
            except subprocess.TimeoutExpired:
                сам.процесс.kill()
                исход = сам.процесс.wait(timeout=2)
        except (OSError, subprocess.TimeoutExpired) as сбой:
            ошибка = сбой
            исход = -1
        finally:
            сам.процесс.stdout.close()
        if тип is None:
            требовать(ошибка is None and исход == 0, 'пакетное чтение Git завершилось отказом')

    def проверить_срок(сам):
        требовать(time.monotonic() < сам.срок, 'истёк срок пакетного чтения Git')

    def учесть_путь(сам, путь):
        сам.проверить_срок()
        сам.развёрнуто += 1
        сам.байтов_путей += len(путь.encode('utf-8'))
        требовать(сам.развёрнуто <= сам.предел_развёрнутых_записей
            and сам.байтов_путей <= сам.предел_байтов_путей,
            'превышен бюджет развёрнутых записей Git-дерева')

    def взять(сам, число):
        требовать(type(число) is int and 0 <= число <= 32 * 1024 * 1024,
            'недопустимый размер сырых данных Git')
        while len(сам.буфер) < число:
            остаток = min(10, сам.срок - time.monotonic())
            требовать(остаток > 0 and select.select([сам.процесс.stdout], [], [], остаток)[0],
                'истёк срок пакетного чтения Git')
            часть = os.read(сам.процесс.stdout.fileno(), 65536)
            требовать(bool(часть), 'усечённый ответ пакетного Git')
            сам.буфер.extend(часть)
        результат = bytes(сам.буфер[:число])
        del сам.буфер[:число]
        return результат
    def прочитать(сам, идентификатор, тип, *, сохранить=False):
        сам.проверить_срок()
        полный_идентификатор(идентификатор)
        требовать(идентификатор != '0' * 40, 'нулевой OID не является объектом')
        if идентификатор in сам.метаданные:
            требовать(сам.метаданные[идентификатор]['тип'] == тип, 'неверный тип сырого Git-объекта')
            if not сохранить or идентификатор in сам.данные:
                return сам.данные.get(идентификатор)
        требовать(len(сам.метаданные) < 200000, 'превышен бюджет объектов Git')
        сам.процесс.stdin.write(идентификатор.encode() + b'\n')
        сам.процесс.stdin.flush()
        заголовок = bytearray()
        while not заголовок.endswith(b'\n'):
            требовать(len(заголовок) < 160, 'недопустимый заголовок пакетного Git')
            заголовок.extend(сам.взять(1))
        совпадение = re.fullmatch(rb'([0-9a-f]{40}) (commit|tree|blob) (0|[1-9][0-9]*)\n', заголовок)
        требовать(совпадение is not None, 'неполный либо неизвестный объект Git')
        выбранный, фактический_тип, размер = совпадение.groups()
        требовать(выбранный.decode() == идентификатор and фактический_тип.decode() == тип,
            'неверный OID либо тип сырого Git-объекта')
        размер = int(размер)
        требовать(размер <= 32 * 1024 * 1024 and сам.байтов + размер <= 2 * 1024 ** 3,
            'превышен бюджет сырых байтов Git')
        сам.байтов += размер
        сырой_хэш = hashlib.sha1(фактический_тип + b' ' + str(размер).encode() + b'\0')
        отпечаток = hashlib.sha256()
        части = []
        остаток = размер
        while остаток:
            часть = сам.взять(min(остаток, 65536))
            сырой_хэш.update(часть)
            отпечаток.update(часть)
            if сохранить:
                части.append(часть)
            остаток -= len(часть)
        требовать(сам.взять(1) == b'\n', 'нет конечного LF пакетного Git')
        требовать(сырой_хэш.hexdigest() == идентификатор, 'Git-объект не соответствует сырым байтам')
        сведения = {'тип': тип, 'sha256': отпечаток.hexdigest(), 'байты': размер}
        прежние = сам.метаданные.get(идентификатор)
        требовать(прежние is None or прежние == сведения, 'Git-объект изменился при чтении')
        сам.метаданные[идентификатор] = сведения
        if сохранить:
            сам.данные[идентификатор] = b''.join(части)
            return сам.данные[идентификатор]
        return None


def разобрать_сырой_коммит(данные):
    требовать(b'\n\n' in данные, 'неполный заголовок сырого коммита')
    строки = данные.split(b'\n\n', 1)[0].split(b'\n')
    требовать(bool(строки) and строки[0].startswith(b'tree '), 'нет начального дерева коммита')
    деревья = [э[5:].decode('ascii') for э in строки if э.startswith(b'tree ')]
    позиция = 1
    родители = []
    while позиция < len(строки) and строки[позиция].startswith(b'parent '):
        родители.append(строки[позиция][7:].decode('ascii'))
        позиция += 1
    требовать(not any(э.startswith((b'parent ', b'tree ')) for э in строки[позиция:]),
        'поздний структурный заголовок сырого коммита')
    требовать(len(деревья) == 1 and len(родители) == len(set(родители))
        and len(родители) <= 256, 'неоднозначные tree/parent сырого коммита')
    for идентификатор in [*деревья, *родители]:
        полный_идентификатор(идентификатор)
        требовать(идентификатор != '0' * 40, 'нулевой OID сырого коммита')
    return {'дерево': деревья[0], 'родители': родители}


def замкнуть_историю(читатель, корни, *, граф=None):
    граф = {} if граф is None else граф
    очередь = list(корни)
    while очередь:
        читатель.проверить_срок()
        идентификатор = очередь.pop()
        if идентификатор in граф:
            continue
        сведения = разобрать_сырой_коммит(читатель.прочитать(идентификатор, 'commit', сохранить=True))
        читатель.данные.pop(идентификатор)
        граф[идентификатор] = сведения
        очередь.extend(сведения['родители'])
    return граф


def общий_сырой_предок(граф, результат, код):
    def предки(начало):
        итог = set()
        очередь = [начало]
        while очередь:
            идентификатор = очередь.pop()
            if идентификатор not in итог:
                итог.add(идентификатор)
                очередь.extend(граф[идентификатор]['родители'])
        return итог
    общие = предки(результат) & предки(код)
    не_лучшие = {родитель for идентификатор in общие for родитель in граф[идентификатор]['родители']}
    лучшие = общие - не_лучшие
    требовать(len(лучшие) == 1, 'нужен единственный общий предок R и K')
    return next(iter(лучшие))


def сырая_таблица(читатель, дерево):
    итог = {}
    очередь = [('', дерево, 0)]
    while очередь:
        читатель.проверить_срок()
        префикс, идентификатор, глубина = очередь.pop()
        требовать(глубина <= 128, 'превышена глубина Git-дерева')
        данные = читатель.прочитать(идентификатор, 'tree', сохранить=True)
        требовать(not префикс or bool(данные), 'пустое вложенное дерево не представлено конечными листьями')
        позиция = 0
        прежний_ключ = None
        имена = set()
        while позиция < len(данные):
            пробел = данные.find(b' ', позиция)
            нуль = данные.find(b'\0', пробел + 1)
            требовать(пробел > позиция and нуль > пробел and нуль + 21 <= len(данные),
                'усечённая запись сырого Git-дерева')
            режим = данные[позиция:пробел]
            требовать(режим in (b'40000', b'100644', b'100755', b'120000', b'160000'),
                'неподдержанный сырой режим дерева')
            имя_байтов = данные[пробел + 1:нуль]
            имя = имя_байтов.decode('utf-8')
            требовать('/' not in имя and имя not in имена, 'повторное либо составное имя дерева')
            имена.add(имя)
            путь = точное_имя(префикс + имя)
            читатель.учесть_путь(путь)
            ключ = имя_байтов + (b'/' if режим == b'40000' else b'')
            требовать(прежний_ключ is None or прежний_ключ < ключ, 'нарушен сырой порядок Git-дерева')
            прежний_ключ = ключ
            дочерний = полный_идентификатор(данные[нуль + 1:нуль + 21].hex())
            требовать(дочерний != '0' * 40, 'нулевой OID записи дерева')
            позиция = нуль + 21
            if режим == b'40000':
                очередь.append((путь + '/', дочерний, глубина + 1))
            else:
                требовать(путь not in итог, 'повторный лист сырого дерева')
                тип = 'commit' if режим == b'160000' else 'blob'
                итог[путь] = (режим.decode(), тип, дочерний)
    return итог


def замкнуть_блобы(читатель, таблицы):
    for таблица_снимка in таблицы:
        for режим, тип, идентификатор in таблица_снимка.values():
            if тип == 'blob':
                читатель.прочитать(идентификатор, 'blob')
    return {идентификатор: {'sha256': э['sha256'], 'байты': э['байты']}
        for идентификатор, э in читатель.метаданные.items() if э['тип'] == 'blob'}


def метаданные(корень, запись, кэш):
    if запись is None:
        return None
    режим, тип, объектный_идентификатор = запись
    требовать(режим in ('100644', '100755') and тип == 'blob',
        'неподдержанный режим переносимого файла базиса')
    if объектный_идентификатор not in кэш:
        данные = объект(корень, объектный_идентификатор, 'blob')
        кэш[объектный_идентификатор] = {'sha256': хэш(данные), 'байты': len(данные)}
    return {'режим': режим, 'тип': тип, 'blob': объектный_идентификатор, **кэш[объектный_идентификатор]}


def состав_базиса(корень, исходное_состояние, принимаемый_базис, принятый_код):
    """Полный детерминированный расчёт, без чтения рабочих исходников и записи."""
    for объектный_идентификатор in (исходное_состояние, принимаемый_базис, принятый_код):
        полный_идентификатор(объектный_идентификатор)
    требовать(len({исходное_состояние, принимаемый_базис, принятый_код}) == 3, 'R, B и K должны различаться')
    корень = корень_гит(корень)
    with ПакетСырыхОбъектов(корень) as читатель:
        граф = замкнуть_историю(читатель, (принимаемый_базис, исходное_состояние, принятый_код))
        сведения = {имя: граф[идентификатор] for имя, идентификатор in (('R', исходное_состояние), ('B', принимаемый_базис), ('K', принятый_код))}
        требовать(сведения['B']['родители'] == [принятый_код, исходное_состояние], 'B требует ровно родителей [K,R]')
        общий_предок = общий_сырой_предок(граф, исходное_состояние, принятый_код)
        т = {имя: сырая_таблица(читатель, граф[идентификатор]['дерево'])
            for имя, идентификатор in (('X', общий_предок), ('R', исходное_состояние), ('K', принятый_код), ('B', принимаемый_базис))}
        кэш = замкнуть_блобы(читатель, т.values())
    коллизии(list(т.values()))
    вклад_состояния = изменения(т['X'], т['R']); вклад_кода = изменения(т['X'], т['K'])
    пересечения = вклад_состояния & вклад_кода
    входящие = изменения(т['R'], т['B'])
    for имя in входящие:
        for ключ in ('R', 'B'):
            запись = т[ключ].get(имя)
            требовать(запись is None or (запись[0] in ('100644', '100755')
                and запись[1] == 'blob'), 'неподдержанный режим переносимого файла базиса')
    все = set().union(*(set(таб) for таб in т.values()))
    for имя in все - пересечения:
        источник = 'R' if имя in вклад_состояния else 'K' if имя in вклад_кода else 'X'
        требовать(т['B'].get(имя) == т[источник].get(имя),
            'не сохранён непересекающийся вклад ' + источник + ': ' + имя)
    прямой = гит(корень, 'diff-tree', '--no-commit-id', '--name-only', '--no-renames',
        '--no-ext-diff', '-r', '-z', исходное_состояние, принимаемый_базис)
    имена = [точное_имя(э.decode('utf-8')) for э in прямой.split(b'\0') if э]
    требовать(len(имена) == len(set(имена)) and set(имена) == входящие,
        'прямой R→B состав не совпал с полными деревьями')
    порядок = lambda набор: sorted(набор, key=lambda п: п.encode('utf-8'))
    версии = lambda имя, ключи: {к: метаданные(корень, т[к].get(имя), кэш) for к in ключи}
    состав = []
    for имя in порядок(входящие):
        до = т['R'].get(имя); после = т['B'].get(имя)
        статус = 'A' if до is None else 'D' if после is None else 'M'
        состав.append({'путь': имя, 'статус': статус, **версии(имя, ('R', 'B'))})
    return {'схема': СХЕМА_СОСТАВА, 'R': исходное_состояние, 'B': принимаемый_базис, 'K': принятый_код,
        'дерево': сведения['B']['дерево'], 'родители': [принятый_код, исходное_состояние], 'общий_предок': общий_предок,
        'входящий_состав': состав,
        'пересечения': [{'путь': п, **версии(п, ('X', 'R', 'K', 'B'))} for п in порядок(пересечения)],
        'сохранённые': [{'путь': п, **версии(п, ('R', 'B'))} for п in порядок(вклад_состояния - вклад_кода)]}


def сверить_состав(расчёт, приёмка):
    """Сверить выбранное отдельно свидетельство; это также не FF-допуск."""
    поля(приёмка, {'состав', 'решения'})
    поля(расчёт, {'схема', 'R', 'B', 'K', 'дерево', 'родители', 'общий_предок',
        'входящий_состав', 'пересечения', 'сохранённые'})
    требовать(расчёт['схема'] == СХЕМА_СОСТАВА
        and байты(расчёт) == байты(приёмка['состав']), 'приёмка не связывает весь точный состав')
    решения = приёмка['решения']
    требовать(type(решения) is list, 'решения пересечений должны быть массивом')
    имена = []
    for решение in решения:
        поля(решение, {'путь', 'описание'})
        имена.append(точное_имя(решение['путь']))
        требовать(type(решение['описание']) is str and bool(решение['описание'].strip()),
            'пересечение требует конкретного решения ROOT')
    требовать(имена == [э['путь'] for э in расчёт['пересечения']],
        'неполный, повторный либо чужой список решений пересечений')
    return расчёт


def сверить_защищённые(корень, исходное_состояние, принимаемый_базис, защищённые):
    """Точный состав первого результата выбирается приёмкой, без угадывания имён."""
    полный_идентификатор(исходное_состояние); полный_идентификатор(принимаемый_базис)
    корень = корень_гит(корень)
    коммит(корень, исходное_состояние); коммит(корень, принимаемый_базис)
    требовать(type(защищённые) is list and bool(защищённые),
        'нужен независимо выбранный непустой защищённый состав R')
    таблица_состояния = таблица(корень, исходное_состояние); таблица_базиса = таблица(корень, принимаемый_базис); кэш = {}; имена = []
    for выбранный in защищённые:
        поля(выбранный, {'путь', 'режим', 'тип', 'blob', 'sha256', 'байты'})
        имя = точное_имя(выбранный['путь']); имена.append(имя)
        требовать(имя in таблица_состояния, 'защищённый путь отсутствует в R')
        исходный = {'путь': имя, **метаданные(корень, таблица_состояния[имя], кэш)}
        требовать(байты(выбранный) == байты(исходный),
            'независимо выбранный защищённый состав не совпал с R')
        требовать(таблица_базиса.get(имя) == таблица_состояния[имя], 'защищённый путь R подменён в B: ' + имя)
        результат = {'путь': имя, **метаданные(корень, таблица_базиса[имя], кэш)}
        требовать(байты(результат) == байты(выбранный), 'не сохранены защищённые сырые байты R')
    требовать(len(имена) == len(set(имена)), 'повторный защищённый путь R')
    коллизии([{п: таблица_состояния[п] for п in имена}])
    return защищённые


def исторический_защищённый_состав(корень, исходное_состояние,
        выбранный_акт, выбранные_полномочия, идентичность):
    """Вывести весь замороженный состав первого цикла; запись не разрешается."""
    поля(идентичность, ИДЕНТИЧНОСТЬ_ПЕРВОГО_ЦИКЛА)
    for имя in ИДЕНТИЧНОСТЬ_ПЕРВОГО_ЦИКЛА:
        требовать(type(идентичность[имя]) is str and bool(идентичность[имя].strip()),
            'пустая идентичность первого цикла')
    for имя in ('координатор', 'владелец'):
        требовать(str(uuid.UUID(идентичность[имя])) == идентичность[имя],
            'неканонический UUID первого цикла')
    требовать(идентичность['координатор'] != идентичность['владелец'],
        'координатор не является дочерним владельцем')
    полный_идентификатор(исходное_состояние)
    корень = корень_гит(корень)
    with ПакетСырыхОбъектов(корень) as читатель:
        граф = {}
        снимки = {}

        def снимок(коммит_источника):
            полный_идентификатор(коммит_источника)
            if коммит_источника not in снимки:
                замкнуть_историю(читатель, (коммит_источника,), граф=граф)
                снимки[коммит_источника] = сырая_таблица(читатель, граф[коммит_источника]['дерево'])
            return снимки[коммит_источника]

        def источник(выбор):
            поля(выбор, {'коммит', 'путь', 'sha256'})
            требовать(type(выбор['sha256']) is str and re.fullmatch('[0-9a-f]{64}', выбор['sha256']),
                'нет сырого SHA исторического источника')
            имя = точное_имя(выбор['путь'])
            требовать(not any(э.startswith('.') for э in имя.split('/')), 'скрытый исторический источник')
            запись = снимок(выбор['коммит']).get(имя)
            требовать(запись is not None and запись[:2] == ('100644', 'blob'),
                'исторический источник не является обычным blob')
            данные = читатель.прочитать(запись[2], 'blob', сохранить=True)
            требовать(0 < len(данные) <= 1024 * 1024 and хэш(данные) == выбор['sha256'],
                'подменены сырые байты исторического источника')
            return данные

        def предок(ранний, поздний):
            замкнуть_историю(читатель, (ранний, поздний), граф=граф)
            очередь = [поздний]; посещённые = set()
            while очередь:
                читатель.проверить_срок()
                нынешний = очередь.pop()
                if нынешний == ранний:
                    return True
                if нынешний not in посещённые:
                    посещённые.add(нынешний); очередь.extend(граф[нынешний]['родители'])
            return False

        таблица_состояния = снимок(исходное_состояние)
        коллизии([таблица_состояния])
        запись_ожиданий = таблица_состояния.get(ПУТЬ_ОЖИДАНИЙ)
        требовать(запись_ожиданий is not None and запись_ожиданий[:2] == ('100644', 'blob'),
            'нет обычного исторического expected первого результата')
        данные_ожиданий = читатель.прочитать(запись_ожиданий[2], 'blob', сохранить=True)
        требовать(0 < len(данные_ожиданий) <= 1024 * 1024, 'исторический expected превышает границу')
        ожидания = разобрать(данные_ожиданий)
        поля(ожидания, {'схема', 'основание', 'предпросмотр'} | ИДЕНТИЧНОСТЬ_ПЕРВОГО_ЦИКЛА)
        требовать(ожидания['схема'] == 'fum.ожидаемое-состояние-узла.1'
            and all(ожидания[к] == идентичность[к] for к in ИДЕНТИЧНОСТЬ_ПЕРВОГО_ЦИКЛА),
            'другая идентичность первого результата')
        вход = ожидания['предпросмотр']
        поля(вход, {'схема', 'координатор', 'постановка_выбора', 'полнота_перечня', 'исполнители'})
        требовать(вход['схема'] == 'fum.вход-предпросмотра-продолжения.2'
            and вход['координатор'] == идентичность['координатор']
            and вход['полнота_перечня'] is False and type(вход['исполнители']) is list
            and len(вход['исполнители']) == 1, 'неверный исторический перечень первого владельца')
        актёр = вход['исполнители'][0]
        поля(актёр, {'задача', 'хост', 'владелец', 'поручение', 'решение_координатора',
            'снимок', 'доставка', 'необязательная_инфраструктура'})
        требовать(актёр['задача'] == актёр['владелец'] == идентичность['владелец']
            and type(актёр['хост']) is str and bool(актёр['хост'].strip())
            and актёр['снимок'] is None and актёр['доставка'] is None
            and актёр['необязательная_инфраструктура'] is False,
            'чужой или live-владелец первого результата')
        выбор_акта = актёр['поручение']
        поля(выбор_акта, {'коммит', 'путь', 'sha256', 'координатор', 'исполнитель'})
        требовать({к: выбор_акта[к] for к in ('коммит', 'путь', 'sha256')} == выбранный_акт
            and выбор_акта['координатор'] == идентичность['координатор']
            and выбор_акта['исполнитель'] == идентичность['владелец'],
            'исторический ACT не совпал с независимым выбором')
        акт = разобрать(источник(выбранный_акт))
        поля(акт, {'схема', 'координатор', 'исполнитель', 'ветка', 'область',
            'постановка', 'хэш_нативного_поручения', 'полномочия_узла'})
        требовать(акт['схема'] == 'fum.поручение-дочерней-контрольной-точки.2'
            and акт['координатор'] == идентичность['координатор']
            and акт['исполнитель'] == идентичность['владелец']
            and акт['полномочия_узла'] == выбранные_полномочия,
            'исторический ACT требует выбранных полномочий первого владельца')
        требовать(type(акт['хэш_нативного_поручения']) is str
            and re.fullmatch('[0-9a-f]{64}', акт['хэш_нативного_поручения']),
            'нет SHA нативного ACT первого цикла')
        источник(акт['постановка'])
        полномочия = разобрать(источник(выбранные_полномочия))
        поля(полномочия, ИДЕНТИЧНОСТЬ_ПЕРВОГО_ЦИКЛА | {'схема', 'ветка', 'хэш_корня',
            'начальный_коммит', 'исходный_коммит', 'путь', 'цели', 'контрольная_ветка'})
        требовать(полномочия['схема'] == 'fum.полномочия-ветки-состояния-узла.1'
            and all(полномочия[к] == идентичность[к] for к in ИДЕНТИЧНОСТЬ_ПЕРВОГО_ЦИКЛА)
            and полномочия['ветка'] == акт['ветка'] == 'refs/heads/fum-lab/fum'
            and полномочия['путь'] == ПУТЬ_ОЖИДАНИЙ
            and акт['область'] == полномочия['цели']
            and акт['постановка']['коммит'] == полномочия['начальный_коммит'],
            'ACT и исторические полномочия первого цикла расходятся')
        требовать(type(полномочия['хэш_корня']) is str
            and re.fullmatch('[0-9a-f]{64}', полномочия['хэш_корня']),
            'неверный исторический хэш дерева владельца')
        контроль = полномочия['контрольная_ветка']
        требовать(type(контроль) is str and контроль.startswith('refs/heads/codex/'),
            'нет отдельного исторического control ref')
        гит(корень, 'check-ref-format', контроль)
        требовать(предок(полномочия['начальный_коммит'], полномочия['исходный_коммит'])
            and предок(полномочия['начальный_коммит'], исходное_состояние)
            and предок(выбранные_полномочия['коммит'], выбранный_акт['коммит']),
            'нет независимой истории первого цикла')
        требовать(ожидания['основание'] == вход['постановка_выбора'] == актёр['решение_координатора'],
            'разные решения исторического первого цикла')
        решение = разобрать(источник(актёр['решение_координатора']))
        поля(решение, {'схема', 'координатор', 'задача', 'хост', 'этап', 'событие', 'поручение',
            'владелец', 'ход', 'состояние', 'остаток', 'ожидание', 'результат', 'план_доставки', 'эффекты'})
        требовать(решение['схема'] == 'fum.сохранённое-решение-root.1'
            and решение['координатор'] == идентичность['координатор']
            and решение['задача'] == решение['владелец'] == идентичность['владелец']
            and решение['хост'] == актёр['хост'] and решение['поручение'] == выбор_акта
            and решение['состояние'] == 'открыт' and решение['остаток'] is True
            and решение['ожидание'] is None and решение['результат'] is None
            and решение['план_доставки'] is None, 'решение ROOT не выбрало первый ACT')
        for имя in ('этап', 'событие'):
            требовать(type(решение[имя]) is str and bool(решение[имя].strip()), 'пустое событие решения ROOT')
        требовать(решение['ход'] is None or type(решение['ход']) is str and bool(решение['ход'].strip()),
            'неверный ход решения ROOT')
        поля(решение['эффекты'], {'отправка', 'репозиторий'})
        требовать(all(э in ('не было', 'подтверждён', 'unknown') for э in решение['эффекты'].values()),
            'неверные исторические эффекты решения ROOT')
        цели = полномочия['цели']
        требовать(type(цели) is list and len(цели) == 8 and all(type(э) is str for э in цели)
            and len(set(цели)) == 8, 'неполный замороженный состав первого цикла')
        for имя in цели:
            точное_имя(имя)
            требовать(not any(э.startswith('.') for э in имя.split('/')), 'скрытая замороженная цель')
        служебные = {'Журнал/README.md', 'Индексы/markdown-файлы-по-времени-редактирования.md'}
        замороженные = set(цели) - служебные
        запросы = [э for э in замороженные
            if len(части := PurePosixPath(э).parts) == 3
            and части[0] == 'Журнал' and части[2] == 'запрос.md']
        требовать(служебные <= set(цели) and len(замороженные) == 6 and len(запросы) == 1,
            'нужны ровно шесть замороженных файлов и одна пара Журнала')
        папка = PurePosixPath(запросы[0]).parent
        обязательные = {ПУТЬ_ОЖИДАНИЙ, запросы[0], str(папка / 'отчёт.md'),
            str(папка / 'материалы' / 'история-модели.json')}
        запуски = замороженные - обязательные
        префикс = str(папка / 'материалы' / 'запуски-проверок') + '/'
        требовать(обязательные <= замороженные and len(запуски) == 2
            and all(э.startswith(префикс) and re.fullmatch(
                r'[1-9][0-9]*_[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\.json', э[len(префикс):])
                for э in запуски), 'неверный конечный состав исторических запусков')
        требовать({э for э in таблица_состояния if э.startswith(префикс)} == запуски,
            'замороженные исторические запуски не совпали с полным составом полномочий')
        результат = []
        for имя in sorted(замороженные):
            запись = таблица_состояния.get(имя)
            требовать(запись is not None and запись[:2] == ('100644', 'blob'),
                'замороженный путь отсутствует или имеет другой режим: ' + имя)
            читатель.прочитать(запись[2], 'blob')
            сведения = читатель.метаданные[запись[2]]
            результат.append({'путь': имя, 'режим': запись[0], 'тип': запись[1], 'blob': запись[2],
                'sha256': сведения['sha256'], 'байты': сведения['байты']})
        коллизии([{э['путь']: таблица_состояния[э['путь']] for э in результат}])
        return результат


def сверить_первый_цикл(корень, исходное_состояние, принимаемый_базис,
        выбранный_акт, выбранные_полномочия, идентичность, заявленный_состав):
    """Полная защита выводится дважды из Git, без доверия к перечню заявителя."""
    исходный = исторический_защищённый_состав(корень, исходное_состояние,
        выбранный_акт, выбранные_полномочия, идентичность)
    требовать(type(заявленный_состав) is list and len(заявленный_состав) == len(исходный),
        'нужен полный независимо выведенный защищённый состав первого цикла')
    for запись in заявленный_состав:
        поля(запись, {'путь', 'режим', 'тип', 'blob', 'sha256', 'байты'})
    требовать(байты(заявленный_состав) == байты(исходный),
        'полный защищённый состав не совпал с независимо выведенным R')
    в_базисе = исторический_защищённый_состав(корень, принимаемый_базис,
        выбранный_акт, выбранные_полномочия, идентичность)
    требовать(байты(в_базисе) == байты(исходный), 'замороженные сырые байты первого цикла изменены в B')
    return исходный

def _сумма_опоры(значение):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение),
        'неверная сумма исторической опоры')


def _число_опоры(значение):
    требовать(type(значение) is int and значение >= 0, 'неверное целое исторической опоры')


def _идентификатор_опоры(значение):
    требовать(type(значение) is str and str(uuid.UUID(значение)) == значение,
        'неверный UUID исторической опоры')


def _путь_опоры(значение):
    требовать(type(значение) is str and Path(значение).is_absolute()
        and str(Path(значение)) == значение and '..' not in Path(значение).parts
        and not any(unicodedata.category(э).startswith('C') for э in значение),
        'неверный абсолютный путь исторической опоры')


def _позиция_опоры(значение):
    поля(значение, {'начало','конец','sha256'})
    _число_опоры(значение['начало']); _число_опоры(значение['конец'])
    требовать(значение['начало'] < значение['конец'], 'обратная позиция исторической опоры')
    _сумма_опоры(значение['sha256'])


def _личность_опоры(значение):
    требовать(type(значение) is list and len(значение) == 4
        and all(type(э) is str and э and '\n' not in э and '\x00' not in э for э in значение)
        and re.fullmatch(r'-?\d+', значение[2]) and re.fullmatch(r'[+-]\d{4}', значение[3]),
        'неверная буквальная identity исторической опоры')


def _разобрать_личность_результата(значение):
    требовать(type(значение) is str, 'результат требует буквальную строку raw Git identity')
    совпадение = re.fullmatch(r'([^\n<>]+) <([^\n<>]+)> (-?\d+) ([+-]\d{4})', значение)
    требовать(совпадение is not None, 'неверная буквальная identity результата')
    итог = list(совпадение.groups()); _личность_опоры(итог)
    return итог


def _сырой_результат_опоры(данные, идентификатор):
    """OID и все шесть полей выводятся из буквального Git-объекта."""
    требовать(type(данные) is bytes and hashlib.sha1(b'commit '
        + str(len(данные)).encode()+b'\0'+данные).hexdigest() == идентификатор,
        'сырые байты результата не соответствуют OID')
    структура = разобрать_сырой_коммит(данные)
    заголовок, сообщение = данные.split(b'\n\n', 1)
    итог = {'коммит': идентификатор, **структура, 'сообщение_sha256': хэш(сообщение)}
    for ключ, префикс in (('автор', b'author '), ('коммиттер', b'committer ')):
        строки = [э[len(префикс):] for э in заголовок.splitlines() if э.startswith(префикс)]
        требовать(len(строки) == 1, 'повторная или отсутствующая identity сырого результата')
        итог[ключ] = строки[0].decode('utf-8')
        _разобрать_личность_результата(итог[ключ])
    return итог



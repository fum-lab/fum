"""Закреплённый план читается независимо от текущего Журнала; эффект запрещён."""
from pathlib import Path
import re
import time

import план_журнала_писателя_состояния as генератор

требовать = генератор.требовать
поля = генератор.полномочия.поля
гит = генератор.гит
хэш = генератор.хэш
ПОЛЯ = {'схема', 'ветка', 'исходный_коммит', 'хэш_корня', 'журнал', 'метка',
    'заголовок', 'время', 'происхождение_времени', 'первоначальный_запрос', 'предыдущий_этап',
    'команды', 'источники_команд', 'строитель', 'файлы'} | генератор.полномочия.ИДЕНТИЧНОСТЬ


def _SHA(значение):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение), 'нужен сырой SHA256 плана')


def _команды(п):
    источники = п['источники_команд']; команды = п['команды']; ROOT = п['координатор']
    требовать(type(источники) is list and 1 <= len(источники) <= 16
        and type(команды) is list and 1 <= len(команды) <= 2048, 'неверный конечный состав команд плана')
    номера = []; позиции = {}; индекс = 0
    for источник in источники:
        поля(источник, {'задача', 'граница_снимка', 'экземпляры'})
        требовать(источник['задача'] == ROOT, 'чужой источник команд плана')
        граница = источник['граница_снимка']; выбор = источник['экземпляры']
        поля(граница, {'sha256', 'граница', 'неоднозначные_экземпляры'}); _SHA(граница['sha256'])
        требовать(type(граница['граница']) is int and граница['граница'] > 0, 'неверная граница снимка')
        требовать(type(выбор) is list and 1 <= len(выбор) <= 128, 'неверный выбор экземпляров')
        неизвестные = граница['неоднозначные_экземпляры']
        требовать(type(неизвестные) is list, 'нужен сохранённый список неоднозначности')
        for номер in [*выбор, *неизвестные]: _SHA(номер)
        требовать(len(неизвестные) == len(set(неизвестные)) and not set(выбор).intersection(неизвестные),
            'неоднозначная команда не входит в выбранный план')
        for номер in выбор:
            требовать(индекс < len(команды), 'недостающая команда плана')
            команда = команды[индекс]; индекс += 1
            поля(команда, {'задача', 'экземпляр', 'позиция', 'текст'})
            требовать(команда['задача'] == ROOT and команда['экземпляр'] == номер
                and type(команда['текст']) is str and bool(команда['текст']), 'нарушен порядок команд плана')
            поз = команда['позиция']; поля(поз, {'начало', 'конец', 'sha256'}); _SHA(поз['sha256'])
            ключ = граница['sha256']
            требовать(type(поз['начало']) is int and type(поз['конец']) is int
                and позиции.get(ключ, 0) <= поз['начало'] < поз['конец'] <= граница['граница'],
                'неверная позиция или порядок raw spans')
            позиции[ключ] = поз['конец']; номера.append(номер)
    требовать(индекс == len(команды) and len(номера) == len(set(номера)), 'лишняя или повторная команда плана')


def _строитель(корень, п):
    ресурсы = [('scripts/request_folder_layout.py', Path(генератор.этап.каркас.__file__)),
        ('шаблоны/запрос.md.шаблон', генератор.этап.каркас.КАТАЛОГ_ШАБЛОНОВ/'запрос.md.шаблон'),
        ('шаблоны/отчёт.md.шаблон', генератор.этап.каркас.КАТАЛОГ_ШАБЛОНОВ/'отчёт.md.шаблон')]
    требовать(type(п['строитель']) is list and len(п['строитель']) == 3, 'нужны три ресурса builder')
    for выбор, (путь, живой) in zip(п['строитель'], ресурсы):
        поля(выбор, {'коммит', 'путь', 'sha256'}); _SHA(выбор['sha256'])
        требовать(выбор['коммит'] == п['исходный_коммит'] and выбор['путь'] == генератор.СТРОИТЕЛЬ+путь,
            'builder должен быть точно выбран на H')
        данные = гит.объект_файла(корень, выбор['коммит'], выбор['путь'])
        требовать(хэш(данные) == выбор['sha256']
            and данные == генератор.читатель.прочитать_файл(живой, предел=генератор.читатель.ПРЕДЕЛ),
            'подмена builder или шаблона')


def _каркас(корень, п):
    """Чистые части stock-builder; не читаем нынешнюю пару и её отчёт."""
    к = генератор.этап.каркас
    _, запрос, отчёт = к._каркас_начала(корень, п['журнал'], п['метка'], п['заголовок'],
        п['координатор'], [э['текст'] for э in п['команды']])
    подсказка = 'зафиксировать получение канонической пары времени рабочей сессии.'
    требовать(запрос.count(подсказка) == 1, 'изменился слот происхождения времени builder')
    запрос = запрос.replace(подсказка, п['происхождение_времени'])
    запрос = к._request_document(п['журнал'], п['заголовок'], None, None,
        [э['текст'] for э in п['команды']], п['координатор'], {}, запрос, навигация_отложена=True)
    отчёт = к._report_document(п['заголовок'], п['журнал'], отчёт)
    return [{'путь': 'Журнал/'+п['журнал']+'/'+имя, 'текст': текст,
        'sha256': хэш(текст.encode()), 'режим': 0o644} for имя, текст in [('запрос.md', запрос), ('отчёт.md', отчёт)]]


def _сверить(данные, корень, профиль):
    начало = time.monotonic_ns()
    требовать(type(данные) is bytes and len(данные) <= генератор.читатель.ПРЕДЕЛ, 'план превышает 64 МиБ')
    п = генератор.читатель.канон.разобрать(данные); поля(п, ПОЛЯ)
    требовать(п['схема'] == 'fum.план-журнала-писателя-состояния.1'
        and п['ветка'] == генератор.полномочия.ВЕТКА, 'неизвестная схема или ref плана')
    for имя in генератор.полномочия.ИДЕНТИЧНОСТЬ: генератор.полномочия.строка(п[имя])
    for имя in ('координатор', 'владелец'): генератор.полномочия.идентификатор(п[имя])
    требовать(п['координатор'] != п['владелец'], 'ROOT не является собственным писателем')
    _SHA(п['хэш_корня']); H = гит.полный_объект(корень, п['исходный_коммит'])
    требовать(type(п['время']) is str and type(п['метка']) is str, 'нужно сохранённое время и метка')
    prefix, label = генератор.генератор.разобрать_время(п['время'])
    требовать(п['журнал'] == prefix+'_'+п['метка'] and п['заголовок'] == генератор.этап.каркас._заголовок_из_метки(п['метка'])
        and п['происхождение_времени'] == 'Получено get-session-time.py --format both: '+prefix+'; '+label+'. Время сохранённого плана.',
        'время, метка, заголовок или происхождение плана разошлись')
    генератор.этап.каркас._validate_stem(п['журнал'], 'закреплённый план')
    for ключ in ('первоначальный_запрос', 'предыдущий_этап'): генератор._история(корень, п[ключ], H, п['координатор'])
    имена = гит.выполнить(корень, 'ls-tree', '-z', H+':Журнал').stdout.split(b'\0')
    требовать(not any(э.split(b'\t', 1)[1].decode().casefold() == п['журнал'].casefold()
        for э in имена if b'\t' in э), 'новая папка уже существовала в H')
    после_истории = time.monotonic_ns(); _строитель(корень, п); _команды(п)
    требовать(type(п['файлы']) is list and len(п['файлы']) == 2, 'нужна ровно одна пара плана')
    for файл in п['файлы']:
        поля(файл, {'путь', 'текст', 'sha256', 'режим'}); _SHA(файл['sha256'])
        требовать(type(файл['текст']) is str and хэш(файл['текст'].encode()) == файл['sha256']
            and type(файл['режим']) is int and файл['режим'] == 0o644, 'подмена текста/SHA/mode пары')
    требовать(п['файлы'] == _каркас(корень, п), 'пара не совпадает с каноническим расчётом builder')
    _строитель(корень, п)
    if профиль is not None:
        профиль.update({'история_наносекунды': после_истории-начало,
            'каркас_и_повтор_наносекунды': time.monotonic_ns()-после_истории,
            'всего_наносекунды': time.monotonic_ns()-начало, 'команд': len(п['команды']),
            'файлов': 2, 'API': 0, 'разборов_native': 0})
    return {'документ': п, 'байты': данные, 'sha256': хэш(данные), 'разрешение_установки': False}


def сверить(данные, *, корень, профиль=None):
    try:
        return _сверить(данные, гит.физический_корень(корень), профиль)
    except (генератор.читатель.канон.приём_делегации.гит.ОшибкаОтчёта,
            генератор.этап.каркас.LayoutError, KeyError, TypeError, UnicodeError) as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def прочитать(выбор, *, корень, профиль=None):
    try:
        корень = гит.физический_корень(корень)
        # Каркас отчёта намеренно содержит маркер незаполненного шаблона.
        # Проверяем raw blob, а не свидетельство выполнения поручения.
        генератор.читатель.канон.источник(выбор)
        гит.полный_объект(корень, выбор['коммит'])
        размер = int(гит.гит(корень, 'cat-file', '-s', выбор['коммит']+':'+выбор['путь']))
        требовать(0 < размер <= генератор.читатель.ПРЕДЕЛ, 'Git-план превышает границу чтения')
        сырые = гит.объект_файла(корень, выбор['коммит'], выбор['путь'])
        требовать(len(сырые) <= генератор.читатель.ПРЕДЕЛ and хэш(сырые) == выбор['sha256'],
            'подмена или превышение границы Git-плана')
        return сверить(сырые, корень=корень, профиль=профиль)
    except (генератор.читатель.канон.приём_делегации.гит.ОшибкаОтчёта, KeyError, TypeError, UnicodeError) as ошибка:
        raise ValueError(str(ошибка)) from ошибка

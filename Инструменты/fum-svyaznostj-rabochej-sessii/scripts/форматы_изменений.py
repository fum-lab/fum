"""Адресная проверка формата рабочих байтов; полный инвентарь не заменяет."""
import importlib.util
import os
from pathlib import Path

КОРЕНЬ_ПРОВЕРКИ = Path(__file__).resolve().parents[3]
КАТАЛОГ = КОРЕНЬ_ПРОВЕРКИ / 'Инструменты/fum-bratislavskaya-proyekciya-pamyati'
ПУТЬ = КАТАЛОГ / 'scripts/братиславская_проекция_памяти.py'
ОПИСАНИЕ = importlib.util.spec_from_file_location('проекция_ранних_форматов', ПУТЬ)
ПРОЕКЦИЯ = importlib.util.module_from_spec(ОПИСАНИЕ)
ОПИСАНИЕ.loader.exec_module(ПРОЕКЦИЯ)


def проверить(корень, охват):
    политика = ПРОЕКЦИЯ.загрузить_политику(КАТАЛОГ / 'контракт-v2.json')
    статус, _, пути = охват.прочитать_статус(корень)
    индекс = ПРОЕКЦИЯ.прочитать_индекс(корень)
    удаления = set()
    части = iter(статус.split(b'\0'))
    for часть in части:
        if not часть:
            continue
        код, имя = часть[:2].decode('ascii'), часть[3:].decode('utf-8')
        if 'U' in код or код in {'AA', 'DD'}:
            raise ValueError('Конфликтное состояние Git: ' + имя)
        if 'D' in код:
            удаления.add(имя)
        if 'R' in код or 'C' in код:
            прежний = next(части).decode('utf-8')
            if 'R' in код:
                удаления.add(прежний)
    ошибки, снимки = [], {}
    пропуски = []
    for имя in пути:
        ПРОЕКЦИЯ.проверить_относительный_путь(имя, 'изменённый путь')
        файл = охват.точный_путь(корень, имя)
        if ПРОЕКЦИЯ.путь_под_префиксом(имя, ПРОЕКЦИЯ.ПРОИЗВОДНОЕ_ПРОСТРАНСТВО):
            пропуски.append(имя)
            continue
        if not os.path.lexists(файл):
            if имя not in удаления:
                raise ValueError('Изменённый файл исчез: ' + имя)
            снимки[имя] = None
            continue
        тип, режим, объект = ПРОЕКЦИЯ.определить_тип_и_режим(корень, имя, индекс)
        if тип == 'ссылка_на_вложенный_репозиторий':
            if имя != ПРОЕКЦИЯ.ПУТЬ_ЗАВИСИМОСТИ or объект != ПРОЕКЦИЯ.РЕВИЗИЯ_ЗАВИСИМОСТИ:
                raise ValueError('gitlink вне закреплённой зависимости: ' + имя)
            пропуски.append(имя)
            continue
        if тип == 'символическая_ссылка':
            raise ValueError('Символическая ссылка требует отдельной политики: ' + имя)
        if ПРОЕКЦИЯ.найти_исключение(имя, политика) is not None:
            пропуски.append(имя)
            continue
        данные = ПРОЕКЦИЯ.безопасно_прочитать_обычный_файл(корень, имя)
        снимки[имя] = (режим, ПРОЕКЦИЯ.хэш_байтов(данные))
        try:
            ПРОЕКЦИЯ.классифицировать_содержимое(корень, имя, политика, данные)
        except ПРОЕКЦИЯ.ОшибкаКонтракта as ошибка:
            ошибки.append(str(ошибка))
    for имя, снимок in снимки.items():
        if снимок is None:
            if os.path.lexists(корень / имя):
                ошибки.append('Удалённый путь появился во время проверки: ' + имя)
            continue
        _, режим, _ = ПРОЕКЦИЯ.определить_тип_и_режим(корень, имя, индекс)
        данные = ПРОЕКЦИЯ.безопасно_прочитать_обычный_файл(корень, имя)
        if (режим, ПРОЕКЦИЯ.хэш_байтов(данные)) != снимок:
            ошибки.append('Байты или режим изменились во время проверки: ' + имя)
    if охват.прочитать_статус(корень)[0] != статус or ПРОЕКЦИЯ.прочитать_индекс(корень) != индекс:
        ошибки.append('Git-состав изменился во время проверки форматов')
    return {'ошибки': ошибки, 'проверено': sum(с is not None for с in снимки.values()),
            'удалено': sum(с is None for с in снимки.values()), 'исключено': len(пропуски)}

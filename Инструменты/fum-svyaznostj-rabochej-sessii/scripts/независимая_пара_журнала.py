"""Чистый план независимой пары; исходный допуск проверяется снаружи."""
import контракт_независимого_журнала as контракт


def построить_пару(вход):
    контракт.поля(вход, {'схема', 'узел', 'корневая_задача', 'писатель', 'основание', 'журнал',
        'заголовок', 'первоначальный_запрос', 'предыдущий_этап', 'команды', 'отчёт'})
    контракт.требовать(вход['схема'] == 'fum.независимая-пара-журнала.1', 'неизвестный формат пары')
    for имя in ('узел', 'заголовок'): контракт.строка(вход[имя])
    for имя in ('корневая_задача', 'писатель'): контракт.идентичность(вход[имя])
    for имя in ('основание', 'первоначальный_запрос'): контракт.селектор(вход[имя])
    if вход['предыдущий_этап'] is not None: контракт.селектор(вход['предыдущий_этап'])
    время = контракт.имя_журнала(вход['журнал'])
    команды = вход['команды']
    контракт.требовать(type(команды) is list and 1 <= len(команды) <= 2048, 'нужны конечные команды')
    экземпляры = set(); позиции = {}; размеры = {}; объём = 0
    for команда in команды:
        контракт.поля(команда, {'задача', 'экземпляр', 'снимок', 'позиция', 'текст', 'sha256_текста'})
        контракт.требовать(команда['задача'] == вход['корневая_задача'], 'чужая команда')
        контракт.отпечаток(команда['экземпляр'])
        контракт.требовать(команда['экземпляр'] not in экземпляры, 'повтор экземпляра команды')
        экземпляры.add(команда['экземпляр'])
        снимок = команда['снимок']; позиция = команда['позиция']
        контракт.поля(снимок, {'sha256', 'байты'}); контракт.отпечаток(снимок['sha256'])
        контракт.поля(позиция, {'начало', 'конец', 'sha256'}); контракт.отпечаток(позиция['sha256'])
        контракт.требовать(type(снимок['байты']) is int and снимок['байты'] > 0
            and type(позиция['начало']) is int and type(позиция['конец']) is int
            and позиции.get(снимок['sha256'], 0) <= позиция['начало'] < позиция['конец'] <= снимок['байты'],
            'неверная граница или порядок команд')
        контракт.требовать(размеры.get(снимок['sha256'], снимок['байты']) == снимок['байты'],
            'противоречивый размер одного снимка')
        размеры[снимок['sha256']] = снимок['байты']
        позиции[снимок['sha256']] = позиция['конец']
        объём += len(контракт.текст({'текст': команда['текст'], 'sha256': команда['sha256_текста']}))
    отчёт = контракт.текст(вход['отчёт'])
    контракт.требовать(объём + len(отчёт) <= контракт.ПРЕДЕЛ_ПАРЫ // 2, 'пара превышает границу')
    # Конечный отчёт и будущие OID результата не определяют идентичность постановки.
    идентификатор = контракт.хэш(контракт.канон({к: в for к, в in вход.items() if к != 'отчёт'}))
    начало = ('# ' + контракт.надпись(вход['заголовок']) + '\n\n'
        + '<!-- FUM-ЖУРНАЛ-ФОРМАТ: 2 -->\n<!-- FUM-ЭТАП-ID: ' + идентификатор + ' -->\n'
        + 'Codex-Thread-ID: ' + вход['корневая_задача'] + '\n\n')
    запрос = начало + 'Отчёт: [перейти](отчёт.md).\n\n## Происхождение\n\n'
    происхождение = {к: вход[к] for к in ('узел', 'писатель', 'основание', 'первоначальный_запрос', 'предыдущий_этап')}
    запрос += контракт.литерал(контракт.канон(происхождение).decode()) + '\n## Исходные команды\n\n'
    for номер, команда in enumerate(команды, 1):
        запрос += '### Команда ' + str(номер) + '\n\n'
        запрос += контракт.литерал(контракт.канон({к: в for к, в in команда.items() if к != 'текст'}).decode()) + '\n'
        запрос += контракт.литерал(команда['текст']) + '\n'
    тело_отчёта = начало + 'Запрос: [перейти](запрос.md).\n\n## Содержательный отчёт\n\n' + контракт.литерал(вход['отчёт']['текст'])
    файлы = []
    for имя, содержание in (('запрос.md', запрос), ('отчёт.md', тело_отчёта)):
        байты = контракт.свежесть(содержание, время)
        файлы.append({'путь': 'Журнал/' + вход['журнал'] + '/' + имя, 'байты': байты,
            'sha256': контракт.хэш(байты), 'режим': 0o644})
    контракт.требовать(sum(len(ф['байты']) for ф in файлы) <= контракт.ПРЕДЕЛ_ПАРЫ, 'пара превышает границу')
    return {'идентификатор': идентификатор, 'файлы': файлы, 'разрешение_установки': False}

"""Проверенный сохранённый UTF-8 JSON → ограниченное представление по указателям."""
import argparse
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
import sys

from компактный_остаток import объект, закодировать
from захват_вывода import открыть_обычный, уложить, записать


СХЕМА = 'fum.компактный-JSON.1'
СУРОГАТ = re.compile('[\ud800-\udfff]')
СИНТАКСИС = re.compile(r'["\\\[\]{}]')


class ОшибкаПредставления(ValueError):
    def __init__(сам, причина):
        сам.причина = причина
        super().__init__(причина)


def требовать(условие, причина):
    if not условие:
        raise ОшибкаПредставления(причина)


@dataclass(frozen=True)
class Число:
    лексема: str


def тип(значение):
    if значение is None:
        return 'null'
    return {bool: 'булево', str: 'строка', list: 'массив', dict: 'объект',
            Число: 'число'}.get(type(значение))


def проверить_глубину(текст, предел):
    глубина = 0
    строка = False
    пропустить = -1
    for совпадение in СИНТАКСИС.finditer(текст):
        позиция = совпадение.start()
        if позиция <= пропустить:
            continue
        знак = совпадение.group()
        if строка:
            if знак == '\\':
                пропустить = позиция + 1
            elif знак == '"':
                строка = False
        elif знак == '"':
            строка = True
        elif знак in '[{':
            глубина += 1
            требовать(глубина <= предел, 'ресурс-глубины')
        elif знак in ']}':
            глубина -= 1


def проверить_дерево(значение, предел):
    стек = [значение]
    число = 0
    while стек:
        узел = стек.pop()
        число += 1
        требовать(число <= предел, 'ресурс-элементов')
        требовать(тип(узел) is not None, 'тип-значения')
        if type(узел) is str:
            требовать(СУРОГАТ.search(узел) is None, 'Unicode')
        elif type(узел) is list:
            требовать(число + len(стек) + len(узел) <= предел, 'ресурс-элементов')
            стек.extend(узел)
        elif type(узел) is dict:
            число += len(узел)  # Ключ — отдельный элемент ресурсного состава.
            требовать(число + len(стек) + len(узел) <= предел, 'ресурс-элементов')
            for ключ in узел:
                требовать(type(ключ) is str and СУРОГАТ.search(ключ) is None, 'Unicode')
            стек.extend(узел.values())


def части_строки(строка):
    yield b'"'
    for начало in range(0, len(строка), 4096):
        # JSON escaping локален каждому символу; кавычки каждого блока убираются.
        yield json.dumps(строка[начало:начало + 4096], ensure_ascii=False)[1:-1].encode('utf-8')
    yield b'"'


def канонические_части(значение):
    if значение is None:
        yield b'null'
    elif type(значение) is bool:
        yield b'true' if значение else b'false'
    elif type(значение) is Число:
        for начало in range(0, len(значение.лексема), 4096):
            yield значение.лексема[начало:начало + 4096].encode('ascii')
    elif type(значение) is str:
        yield from части_строки(значение)
    elif type(значение) is list:
        yield b'['
        for номер, узел in enumerate(значение):
            if номер:
                yield b','
            yield from канонические_части(узел)
        yield b']'
    elif type(значение) is dict:
        yield b'{'
        for номер, ключ in enumerate(sorted(значение)):
            if номер:
                yield b','
            yield from части_строки(ключ)
            yield b':'
            yield from канонические_части(значение[ключ])
        yield b'}'
    else:
        raise ОшибкаПредставления('тип-значения')


def выбрать(значение, указатель):
    требовать(указатель == '' or указатель.startswith('/'), 'указатель-синтаксис')
    if указатель == '':
        return значение
    for часть in указатель[1:].split('/'):
        требовать(re.search(r'~(?![01])', часть) is None, 'указатель-синтаксис')
        ключ = часть.replace('~1', '/').replace('~0', '~')
        if type(значение) is dict:
            требовать(ключ in значение, 'указатель-не-найден')
            значение = значение[ключ]
        elif type(значение) is list:
            требовать(re.fullmatch(r'0|[1-9][0-9]*', ключ) is not None, 'указатель-индекс')
            требовать(len(ключ) <= len(str(len(значение))), 'указатель-не-найден')
            номер = int(ключ)
            требовать(номер < len(значение), 'указатель-не-найден')
            значение = значение[номер]
        else:
            raise ОшибкаПредставления('указатель-проход')
    return значение


def _представить(данные, ожидаемый_хэш, *, указатели, бюджет_байтов=16000,
                глубина=4, элементы=20, скаляр_байтов=256,
                предел_входа=134217728, предел_глубины=128, предел_элементов=1000000):
    """Возвращает полные UTF-8 bytes с LF; ошибки не содержат входных данных."""
    for значение, минимум, максимум in [
        (бюджет_байтов, 0, 1048576), (глубина, 0, 64), (элементы, 0, 1000),
        (скаляр_байтов, 0, 1048576), (предел_входа, 1, 134217728),
        (предел_глубины, 1, 128), (предел_элементов, 1, 1000000)]:
        требовать(type(значение) is int and минимум <= значение <= максимум, 'параметры')
    требовать(type(данные) is bytes and type(ожидаемый_хэш) is str
              and re.fullmatch('[0-9a-f]{64}', ожидаемый_хэш) is not None, 'параметры')
    требовать(type(указатели) is list and 1 <= len(указатели) <= 64
              and all(type(у) is str for у in указатели), 'параметры')
    требовать(len(данные) <= предел_входа, 'ресурс-байтов')
    требовать(hashlib.sha256(данные).hexdigest() == ожидаемый_хэш, 'sha-источника')
    for указатель in указатели:
        требовать(СУРОГАТ.search(указатель) is None, 'указатель-синтаксис')
        требовать(len(указатель) <= бюджет_байтов
                  and len(указатель.encode('utf-8')) <= бюджет_байтов, 'бюджет')
    try:
        текст = данные.decode('utf-8', errors='strict')
    except UnicodeError:
        raise ОшибкаПредставления('Unicode') from None
    проверить_глубину(текст, предел_глубины)

    def запретить_константу(_константа):
        raise ОшибкаПредставления('неконечное-число')

    try:
        значение = json.loads(текст, object_pairs_hook=объект,
            parse_int=Число, parse_float=Число, parse_constant=запретить_константу)
    except ОшибкаПредставления:
        raise
    except RecursionError:
        raise ОшибкаПредставления('ресурс-парсера') from None
    except ValueError as ошибка:
        причина = 'повтор-ключа' if str(ошибка) == 'повтор поля JSON' else 'JSON'
        raise ОшибкаПредставления(причина) from None
    проверить_дерево(значение, предел_элементов)
    сводки = {}

    def сводка(узел):
        ключ = id(узел)
        if ключ not in сводки:
            накопитель = hashlib.sha256()
            размер = 0
            for часть in канонические_части(узел):
                размер += len(часть)
                накопитель.update(часть)
            сводки[ключ] = {'тип': тип(узел), 'канонических_байтов': размер,
                           'sha256': накопитель.hexdigest()}
        return сводки[ключ]

    def метаданные(узел, указатель, причина):
        return {'сокращено': True, 'указатель': указатель, 'причина': причина, **сводка(узел)}

    def сократить(узел, указатель, причина):
        return метаданные(узел, указатель, причина), False, [
            {'указатель': указатель, 'вид': 'метаданные'}]

    def отобразить(узел, указатель, уровень):
        вид = тип(узел)
        состав = сводка(узел)
        if вид in ('строка', 'число') and состав['канонических_байтов'] > скаляр_байтов:
            return сократить(узел, указатель, 'скаляр')
        if type(узел) is Число:
            return {'числовая_лексема': узел.лексема, 'тип': 'число'}, True, [
                {'указатель': указатель, 'вид': 'числовая-лексема'}]
        if type(узел) not in (dict, list):
            return узел, True, []
        if узел and уровень >= глубина:
            return сократить(узел, указатель, 'глубина')
        if len(узел) > элементы:
            return сократить(узел, указатель, 'элементы')
        if состав['канонических_байтов'] > бюджет_байтов:
            return сократить(узел, указатель, 'бюджет')
        if type(узел) is dict and any(len(к) > скаляр_байтов or
            len(к.encode('utf-8')) > скаляр_байтов for к in узел):
            return сократить(узел, указатель, 'ключ')
        результат = {} if type(узел) is dict else []
        полностью = True
        замены = []
        пары = ((к, узел[к]) for к in sorted(узел)) if type(узел) is dict else enumerate(узел)
        for ключ, ребёнок in пары:
            часть = str(ключ).replace('~', '~0').replace('/', '~1')
            адрес = указатель + '/' + часть
            if len(адрес.encode('utf-8')) > бюджет_байтов:
                return сократить(узел, указатель, 'указатель')
            вывод, показано, метки = отобразить(ребёнок, адрес, уровень + 1)
            замены.extend(метки)
            полностью = полностью and показано
            if type(результат) is dict:
                результат[ключ] = вывод
            else:
                результат.append(вывод)
        return результат, полностью, замены

    выборки = []
    узлы = []
    for указатель in указатели:
        узел = выбрать(значение, указатель)
        вывод, полностью, замены = отобразить(узел, указатель, 0)
        узлы.append(узел)
        выборки.append({'указатель': указатель, **сводка(узел),
            'полностью_показано': полностью, 'представление': вывод, 'замены': замены})
    ответ = {'схема': СХЕМА, 'успех': True,
             'источник': {'raw_sha256': ожидаемый_хэш, 'байтов': len(данные)}, 'выборки': выборки}
    try:
        return уложить(ответ, бюджет_байтов)
    except ValueError:
        for запись, узел in zip(выборки, узлы):
            запись['полностью_показано'] = False
            запись['представление'] = метаданные(узел, запись['указатель'], 'бюджет')
            запись['замены'] = [{'указатель': запись['указатель'], 'вид': 'метаданные'}]
        try:
            return уложить(ответ, бюджет_байтов)
        except ValueError:
            raise ОшибкаПредставления('бюджет') from None


def представить(данные, ожидаемый_хэш, **параметры):
    """Закрытый API: bytes + независимый raw SHA; только фиксированные причины."""
    try:
        return _представить(данные, ожидаемый_хэш, **параметры)
    except (MemoryError, RecursionError):
        raise ОшибкаПредставления('ресурс-парсера') from None
    except TypeError:
        raise ОшибкаПредставления('параметры') from None


def состояние(снимок):
    return (снимок.st_dev, снимок.st_ino, снимок.st_size, снимок.st_mtime_ns, снимок.st_ctime_ns)


def представить_файл(путь, ожидаемый_хэш, **параметры):
    try:
        with открыть_обычный(Path(путь)) as поток:
            до = состояние(os.fstat(поток.fileno()))
            предел = параметры.get('предел_входа', 134217728)
            требовать(type(предел) is int and 1 <= предел <= 134217728, 'параметры')
            данные = поток.read(предел + 1)
            требовать(len(данные) <= предел, 'ресурс-байтов')
            ответ = представить(данные, ожидаемый_хэш, **параметры)
            требовать(до == состояние(os.fstat(поток.fileno()))
                      == состояние(Path(путь).lstat()), 'дрейф-источника')
            return ответ
    except ОшибкаПредставления:
        raise
    except (MemoryError, RecursionError):
        raise ОшибкаПредставления('ресурс-парсера') from None
    except (OSError, ValueError, TypeError):
        raise ОшибкаПредставления('источник') from None


class РазборАргументов(argparse.ArgumentParser):
    def error(сам, _сообщение):
        raise ОшибкаПредставления('аргументы')


def главная(аргументы=None):
    аргументы = sys.argv[1:] if аргументы is None else аргументы
    бюджет = 16000
    try:
        бюджеты = []
        for номер, аргумент in enumerate(аргументы):
            if аргумент == '--бюджет-байтов':
                бюджеты.append(аргументы[номер + 1] if номер + 1 < len(аргументы) else '')
            elif аргумент.startswith('--бюджет-байтов='):
                бюджеты.append(аргумент.split('=', 1)[1])
        if бюджеты:
            бюджет = 0  # Неоднозначный/повреждённый бюджет не разрешает диагностику.
            требовать(len(бюджеты) == 1, 'аргументы')
            строка = бюджеты[0]
            if re.fullmatch('[0-9]{1,7}', строка) is None or int(строка) > 1048576:
                бюджет = 0
                raise ОшибкаПредставления('параметры')
            бюджет = int(строка)
        требовать(len(аргументы) <= 160 and all(len(а) <= 1048576 for а in аргументы), 'аргументы')
        разбор = РазборАргументов(add_help=False, allow_abbrev=False)
        разбор.add_argument('--источник', required=True)
        разбор.add_argument('--sha256', required=True)
        разбор.add_argument('--указатель', action='append', required=True)
        for имя, умолчание in [('бюджет-байтов', 16000), ('глубина', 4), ('элементы', 20),
            ('скаляр-байтов', 256), ('предел-входа', 134217728), ('предел-глубины', 128),
            ('предел-элементов', 1000000)]:
            разбор.add_argument('--' + имя, type=int, default=умолчание)
        п = разбор.parse_args(аргументы)
        ответ = представить_файл(п.источник, п.sha256, указатели=п.указатель,
            бюджет_байтов=п.бюджет_байтов, глубина=п.глубина, элементы=п.элементы,
            скаляр_байтов=п.скаляр_байтов, предел_входа=п.предел_входа,
            предел_глубины=п.предел_глубины, предел_элементов=п.предел_элементов)
    except (ОшибкаПредставления, MemoryError, RecursionError) as ошибка:
        причина = ошибка.причина if type(ошибка) is ОшибкаПредставления else 'ресурс-парсера'
        ответ = закодировать({'схема': СХЕМА, 'успех': False, 'причина': причина})
        if len(ответ) <= бюджет:
            вывести(ответ)
        return 2
    return 0 if вывести(ответ) else 2


def вывести(данные):
    try:
        записать(sys.stdout.fileno(), данные)
        return True
    except OSError:
        return False


if __name__ == '__main__':
    raise SystemExit(главная())

СХЕМА_ВЫБОРА = 'fum.выбор-конечного-контура.1'
СХЕМА_СОСТАВА = 'fum.конечный-состав-независимого-контура.1'
# Профиль выбран независимо от пользовательского списка целей и аргументов.
ОТПЕЧАТОК_ПРОФИЛЯ = 'c645d3bca9d1ed22b730048dee4abe13e02437c80a3b1f3e89dbf291291e18ae'


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def байты(объект):
    return (json.dumps(объект, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode('utf-8')


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def разобрать(сырые):
    def пары(элементы):
        объект = {}
        for ключ, значение in элементы:
            требовать(ключ not in объект, 'повторный ключ закрытого выбора: ' + ключ)
            объект[ключ] = значение
        return объект
    def запретить_число(текст):
        raise ValueError('неподдержанное число закрытого выбора: ' + текст)
    return json.loads(сырые, object_pairs_hook=пары, parse_float=запретить_число,
        parse_constant=запретить_число)


def проверенный_профиль(сырые, *, независимый_sha256=None):
    ожидаемый = ОТПЕЧАТОК_ПРОФИЛЯ if независимый_sha256 is None else независимый_sha256
    требовать(хэш(сырые) == ожидаемый, 'неверный независимый отпечаток профиля')
    профиль = разобрать(сырые)
    требовать(профиль['схема'] == 'fum.закреплённый-профиль-независимого-контура.1',
        'неверная схема закреплённого профиля')
    return профиль


def проверить_одобрение(сырые, независимый_sha256, профиль, *, коммит, дерево, генератор):
    """SHA одобрения приходит отдельным внешним аргументом, вне манифеста."""
    требовать(хэш(сырые) == независимый_sha256, 'подменено независимо выбранное одобрение')
    одобрение = разобрать(сырые)
    требовать(type(одобрение) is dict and set(одобрение) == {'схема', 'координатор', 'код',
        'генератор_sha256', 'рецепт_sha256', 'профиль_sha256'}
        and одобрение['схема'] == 'fum.независимое-одобрение-профиля.1', 'неверное одобрение профиля')
    п = проверенный_профиль(профиль, независимый_sha256=одобрение['профиль_sha256'])
    требовать(одобрение['код'] == {'коммит': коммит, 'дерево': дерево}
        and п['происхождение'] == одобрение['код']
        and одобрение['генератор_sha256'] == генератор
        and одобрение['рецепт_sha256'] == п['рецепт_sha256'], 'одобрение не связывает точные K/recipe/generator/profile')
    return одобрение


def точный_путь(значение):
    требовать(type(значение) is str and значение and '\\' not in значение,
        'нужен непустой точный путь')
    путь = PurePosixPath(значение)
    требовать(not путь.is_absolute() and путь.as_posix() == значение
        and all(ч not in ('', '.', '..', '.git') for ч in значение.split('/'))
        and unicodedata.normalize('NFC', значение) == значение, 'неверный путь Git')
    return значение


def гит(корень, *аргументы, вход=None):
    среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_NO_LAZY_FETCH='1', GIT_NO_REPLACE_OBJECTS='1',
        GIT_TERMINAL_PROMPT='0', GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull)
    команда = ['git', '--no-optional-locks', '--no-replace-objects',
        '-c', 'core.hooksPath=' + os.devnull, '-c', 'core.fsmonitor=false',
        '-c', 'protocol.allow=never', '-c', 'submodule.recurse=false',
        '-c', 'fetch.recurseSubmodules=false', '-C', str(корень), *аргументы]
    return subprocess.check_output(команда, input=вход, env=среда)


def прочитать_набор(корень, коммит, пути):
    """Один batch: проверены Git SHA-1, физические байты и режим каждого файла."""
    корень = Path(корень)
    требовать(корень.is_absolute() and корень.resolve() == корень, 'нужен физический корень K')
    требовать(re.fullmatch('[0-9a-f]{40}', коммит) is not None, 'нужен полный коммит K')
    требовать(гит(корень, 'rev-parse', '--show-toplevel').decode().strip() == str(корень),
        'K должен быть настоящим Git-корнем')
    конфиг = гит(корень, 'config', '--local', '--no-includes', '--null', '--list')
    for поле in конфиг.split(b'\0'):
        ключ = поле.split(b'\n', 1)[0].decode().lower()
        требовать(not (ключ.startswith('include') or ключ == 'extensions.partialclone'
            or ключ.startswith('remote.') and ключ.endswith(('.promisor', '.partialclonefilter'))),
            'неполная или include-конфигурация K запрещена')
    требовать(гит(корень, 'rev-parse', '--is-shallow-repository').strip() == b'false',
        'shallow K запрещён')
    требовать(гит(корень, 'rev-parse', коммит + '^{commit}').decode().strip() == коммит,
        'не найден точный коммит K')
    пути = list(пути)
    требовать(пути and len(пути) == len(set(пути)), 'нужен конечный уникальный состав')
    for путь in пути:
        точный_путь(путь)
    требовать(len({п.casefold() for п in пути}) == len(пути), 'коллизия путей K')
    дерево = {}
    for строка in гит(корень, 'ls-tree', '-r', '-z', коммит).split(b'\0'):
        if not строка:
            continue
        мета, имя = строка.split(b'\t', 1)
        режим, тип, объект = мета.decode().split()
        дерево[имя.decode()] = (режим, тип, объект)
    for путь in пути:
        требовать(путь in дерево and дерево[путь][0] in ('100644', '100755')
            and дерево[путь][1] == 'blob', 'отсутствующий или необычный путь Git: ' + путь)
    объекты = list(dict.fromkeys(дерево[п][2] for п in пути))
    поток = гит(корень, 'cat-file', '--batch', вход=('\n'.join(объекты) + '\n').encode('ascii'))
    позиция = 0
    данные = {}
    for объект in объекты:
        конец = поток.index(b'\n', позиция)
        имя, тип, длина = поток[позиция:конец].decode().split()
        размер = int(длина); начало = конец + 1; исходник = поток[начало:начало + размер]
        позиция = начало + размер + 1
        требовать(имя == объект and тип == 'blob' and размер >= 0
            and len(исходник) == размер and поток[позиция - 1:позиция] == b'\n'
            and hashlib.sha1(b'blob ' + str(размер).encode() + b'\0' + исходник).hexdigest() == объект,
            'неверные байты объекта Git')
        данные[объект] = исходник
    требовать(позиция == len(поток), 'лишний хвост Git batch')
    записи = {}
    for относительный in пути:
        путь = корень
        for часть in PurePosixPath(относительный).parts:
            путь /= часть
            требовать(not путь.is_symlink(), 'symlink в пути K')
        до = путь.stat(); режим, _, объект = дерево[относительный]
        требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1, 'нужен обычный файл K')
        сырые = путь.read_bytes(); после = путь.stat()
        свойства = lambda с: (с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink,
            с.st_size, с.st_mtime_ns, с.st_ctime_ns)
        требовать(свойства(до) == свойства(после) and сырые == данные[объект]
            and ('100755' if до.st_mode & 0o111 else '100644') == режим,
            'рабочие байты или режим не равны Git: ' + относительный)
        записи[относительный] = ({'путь': относительный, 'режим': режим,
            'объект': объект, 'sha256': хэш(сырые)}, сырые)
    return записи


def форма_места(узел):
    return хэш(ast.dump(узел, include_attributes=False).encode('utf-8'))


def конечные_строки(узел):
    if isinstance(узел, ast.Constant) and type(узел.value) is str:
        return [узел.value]
    if isinstance(узел, ast.IfExp):
        левый, правый = конечные_строки(узел.body), конечные_строки(узел.orelse)
        return list(dict.fromkeys(левый + правый)) if левый is not None and правый is not None else None
    return None


def проверить_обращения_к_загрузчикам(дерево):
    """Функция загрузки не может скрыться в присваивании или аргументе helper."""
    родители = {дочерний: родитель for родитель in ast.walk(дерево)
        for дочерний in ast.iter_child_nodes(родитель)}
    привязки = {}
    def привязать(имя, значение):
        требовать(имя not in привязки or привязки[имя] == значение,
            'конфликт привязок динамического загрузчика')
        привязки[имя] = значение
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            for имя in узел.names:
                if имя.name.split('.')[0] in {'importlib', 'builtins', 'runpy'}:
                    привязать(имя.asname or имя.name.split('.')[0], имя.name if имя.asname else имя.name.split('.')[0])
        elif isinstance(узел, ast.ImportFrom) and узел.module in {'importlib', 'importlib.util', 'importlib.machinery', 'builtins', 'runpy'}:
            for имя in узел.names:
                привязать(имя.asname or имя.name, узел.module + '.' + имя.name)
    def адрес(узел):
        if isinstance(узел, ast.Name):
            return привязки.get(узел.id, узел.id)
        if isinstance(узел, ast.Attribute):
            основа = адрес(узел.value)
            return основа + '.' + узел.attr if основа else ''
        return ''
    загрузчики = {'importlib.import_module', 'importlib.util.spec_from_file_location',
        'importlib.machinery.SourceFileLoader', 'importlib.machinery.SourcelessFileLoader',
        'importlib.machinery.ExtensionFileLoader',
        'builtins.__import__', 'builtins.compile', 'builtins.exec', 'builtins.eval',
        'runpy.run_path', 'runpy.run_module', '__import__', 'compile', 'exec', 'eval'}
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Name) and узел.id == '__builtins__':
            требовать(False, 'извлечение динамического загрузчика из __builtins__ запрещено')
        if isinstance(узел, ast.Call) and адрес(узел.func) in {'getattr', 'vars', 'builtins.getattr', 'builtins.vars'}:
            требовать(not узел.args or адрес(узел.args[0]).split('.')[0] not in {'importlib', 'builtins', 'runpy'},
                'извлечение динамического загрузчика через рефлексию запрещено')
        if isinstance(узел, ast.Name) and isinstance(узел.ctx, ast.Load) and адрес(узел) in {'importlib', 'builtins', 'runpy'}:
            родитель = родители.get(узел)
            требовать(isinstance(родитель, ast.Attribute) and родитель.value is узел,
                'псевдоним пространства имён загрузчика запрещён')
        if isinstance(узел, ast.Name) and isinstance(узел.ctx, (ast.Store, ast.Del)):
            требовать(узел.id not in привязки, 'затенение привязки динамического загрузчика')
        if isinstance(узел, ast.arg):
            требовать(узел.arg not in привязки, 'затенение аргументом динамического загрузчика')
        if isinstance(узел, (ast.Name, ast.Attribute)) and адрес(узел) in загрузчики:
            родитель = родители.get(узел)
            требовать(isinstance(родитель, ast.Call) and родитель.func is узел,
                'псевдоним динамического загрузчика требует отдельного закрытого контракта')
    return адрес


def буквальные_импорты(узел, адрес):
    if адрес in {'importlib.import_module', '__import__', 'builtins.__import__'}:
        требовать(узел.args, 'нет имени динамического импорта')
        if адрес == 'importlib.import_module':
            требовать(len(узел.args) == 1 and not узел.keywords,
                'неподдержанные параметры динамического импорта')
        else:
            требовать(len(узел.args) <= 5 and not any(isinstance(а, ast.Starred) for а in узел.args),
                'неподдержанные параметры встроенного импорта')
            параметры = {и: з for и, з in zip(('name', 'globals', 'locals', 'fromlist', 'level'), узел.args)}
            for пара in узел.keywords:
                требовать(пара.arg in {'globals', 'locals', 'fromlist', 'level'}
                    and пара.arg not in параметры, 'неподдержанные параметры встроенного импорта')
                параметры[пара.arg] = пара.value
            уровень = параметры.get('level')
            требовать(уровень is None or isinstance(уровень, ast.Constant)
                and type(уровень.value) is int and уровень.value == 0,
                'относительный встроенный импорт не поддержан')
            список = параметры.get('fromlist')
            требовать(список is None or isinstance(список, (ast.Tuple, ast.List)) and not список.elts,
                'неподдержанный дочерний встроенный импорт')
        return конечные_строки(узел.args[0])
    return None


def построить(корень, коммит, выбор, *, профиль=None, независимый_sha256=None):
    закреплённый = проверенный_профиль(профиль, независимый_sha256=независимый_sha256) if профиль is not None else None
    разрешённые_места = {}
    if закреплённый is not None:
        эталон = закреплённый['выбор']
        требовать(type(выбор) is dict and set(выбор) == set(эталон)
            and all(выбор[п] == эталон[п] for п in эталон if п != 'команды'),
            'входы, aliases, ресурсы или места отличаются от закреплённого профиля')
        for место in закреплённый['места']:
            ключ = (место['путь'], место['исходник_sha256'], место['строка'], место['форма_sha256'])
            требовать(ключ not in разрешённые_места, 'повтор закреплённого места')
            разрешённые_места[ключ] = место
    поля = {'схема', 'входы', 'имена', 'динамические_места', 'ресурсы', 'команды'}
    требовать(type(выбор) is dict and set(выбор) == поля and выбор['схема'] == СХЕМА_ВЫБОРА,
        'неизвестный закрытый выбор конечного контура')
    имена = выбор['имена']
    требовать(type(имена) is dict and all(type(и) is str and и
        and и.split('.')[0] not in sys.stdlib_module_names for и in имена),
        'неверный реестр имён или коллизия со стандартной библиотекой')
    for поле in ('входы', 'ресурсы', 'динамические_места', 'команды'):
        требовать(type(выбор[поле]) is list, 'нужен конечный список: ' + поле)
    требовать(выбор['входы'] and выбор['команды'], 'нужны вход и выбранные команды')
    входы = list(выбор['входы'])
    for команда in выбор['команды']:
        требовать(type(команда) is dict and set(команда) == {'путь', 'аргументы'}
            and type(команда['аргументы']) is list
            and all(type(э) is str for э in команда['аргументы']), 'неверная команда CLI')
        требовать(not {'-c', '-m'}.intersection(команда['аргументы']), 'невыбранная форма Python CLI')
        if закреплённый is not None:
            требовать(команда['путь'] in закреплённый['разрешённые_команды'],
                'команда вне неизменного профиля CLI')
        входы.append(команда['путь'])
    все = list(dict.fromkeys([*входы, *имена.values(), *выбор['ресурсы']]))
    записи = прочитать_набор(корень, коммит, все)
    if закреплённый is not None:
        for путь, ожидаемый in закреплённый['исходники'].items():
            требовать(путь in записи and записи[путь][0]['sha256'] == ожидаемый,
                'исходник отличается от закреплённого пути/байтов профиля: ' + путь)
        if 'ресурсы' in закреплённый:
            требовать(закреплённый['ресурсы'] == [записи[п][0] for п in sorted(выбор['ресурсы'])],
                'ресурсы отличаются от независимо выбранного профиля')
    места = {}
    for место in выбор['динамические_места']:
        требовать(type(место) is dict and set(место) == {'путь', 'строка', 'форма_sha256', 'цели', 'основание'}
            and type(место['строка']) is int and место['строка'] > 0
            and type(место['цели']) is dict and (место['цели'] or закреплённый is not None)
            and type(место['основание']) is str and место['основание'].strip(), 'неверное динамическое место')
        ключ = (место['путь'], место['строка'], место['форма_sha256'])
        требовать(ключ not in места and all(имена.get(и) == п for и, п in место['цели'].items()),
            'повторное место или цель вне реестра имён')
        места[ключ] = место
    очередь = list(dict.fromkeys(входы)); код = {}; рёбра = []; использованные = set()
    def импорт(имя, откуда, вид):
        требовать(type(имя) is str and имя and not имя.startswith('.'), 'неверное имя импорта')
        if имя.split('.')[0] in sys.stdlib_module_names:
            return
        требовать(имя in имена, 'импорт отсутствует в конечном реестре: ' + имя)
        цель = имена[имя]
        требовать('.' not in имя and not цель.endswith('/__init__.py'),
            'неподдержанный пакетный импорт')
        рёбра.append({'из': откуда, 'в': цель, 'имя': имя, 'вид': вид})
        if цель not in код and цель not in очередь:
            очередь.append(цель)
    while очередь:
        путь = очередь.pop(0)
        требовать(путь.endswith('.py'), 'исполняемый код должен быть Python')
        запись, исходник = записи[путь]; код[путь] = запись
        дерево = ast.parse(исходник, filename=путь)
        адрес_вызова = проверить_обращения_к_загрузчикам(дерево)
        for узел in ast.walk(дерево):
            if isinstance(узел, ast.Import):
                for псевдоним in узел.names:
                    импорт(псевдоним.name, путь, 'обычный')
            elif isinstance(узел, ast.ImportFrom):
                требовать(not узел.level and узел.module, 'неподдержанный относительный импорт')
                импорт(узел.module, путь, 'обычный')
            elif isinstance(узел, ast.Call):
                адрес = адрес_вызова(узел.func)
                динамический = адрес in {'importlib.util.spec_from_file_location', 'importlib.import_module',
                    '__import__', 'builtins.__import__', 'compile', 'exec', 'eval',
                    'builtins.compile', 'builtins.exec', 'builtins.eval',
                    'importlib.machinery.SourceFileLoader', 'importlib.machinery.SourcelessFileLoader',
                    'importlib.machinery.ExtensionFileLoader', 'runpy.run_path', 'runpy.run_module'}
                if not динамический:
                    continue
                литералы = буквальные_импорты(узел, адрес)
                if литералы is not None:
                    for литерал in литералы:
                        импорт(литерал, путь, 'динамический-литерал')
                    continue
                ключ = (путь, узел.lineno, форма_места(узел))
                требовать(ключ in места, 'необъяснённое динамическое место: ' + путь + ':' + str(узел.lineno))
                разрешённое = разрешённые_места.get((путь, запись['sha256'], узел.lineno, ключ[2]))
                требовать(разрешённое is not None and разрешённое['цели'] == места[ключ]['цели'],
                    'динамическое место не закреплено независимо от заявленных целей')
                использованные.add(ключ)
                for псевдоним in места[ключ]['цели']:
                    импорт(псевдоним, путь, 'динамический-реестр')
    требовать(использованные == set(места), 'лишнее или устаревшее динамическое место')
    return {'схема': СХЕМА_СОСТАВА, 'корень': str(Path(корень)), 'коммит': коммит,
        'выбор_sha256': хэш(байты(выбор)), 'код': [код[п] for п in sorted(код)],
        'имена': {и: п for и, п in sorted(имена.items()) if п in код},
        'ресурсы': [записи[п][0] for п in sorted(выбор['ресурсы'])],
        'входы': list(dict.fromkeys(входы)), 'команды': выбор['команды'],
        'рёбра': sorted(рёбра, key=lambda э: (э['из'], э['в'], э['имя'], э['вид'])),
        'динамические_места': [места[к] for к in sorted(использованные)], 'неизвестные': []}


def сгенерировать_кандидат(корень, коммит, сырые_рецепта):
    """Только данные-кандидат; рецепт и результат отдельно выбирает ROOT.

    Первый рецепт консервативен: AST всего просмотренного subject-кода
    неизменна. Это связывает конечные helper targets со всеми callers и
    bindings; любое смысловое изменение требует нового независимого рецепта.
    """
    рецепт = разобрать(сырые_рецепта)
    поля = {'схема', 'Python', 'эталоны', 'входы', 'разрешённые_команды', 'ресурсы',
        'ресурсы_рендера', 'исходники', 'импортные_коллизии', 'дополнительные_имена', 'динамика', 'модули_допуска'}
    требовать(type(рецепт) is dict and set(рецепт) == поля
        and рецепт['схема'] == 'fum.рецепт-конечного-контура.1'
        and рецепт['Python'] == list(sys.version_info[:2]), 'неизвестный рецепт или Python')
    исходники = рецепт['исходники']
    требовать(type(исходники) is dict and исходники, 'пустая AST-основа рецепта')
    команды = рецепт['разрешённые_команды']; ресурсы = рецепт['ресурсы']
    входы = [*рецепт['входы'], *рецепт['модули_допуска']]
    for список in (входы, команды, ресурсы, рецепт['ресурсы_рендера']):
        требовать(type(список) is list and len(список) == len(set(список)), 'неоднозначный список рецепта')
        for путь in список: точный_путь(путь)
    требовать(set(рецепт['входы']) <= set(команды) <= set(исходники) and set(входы) <= set(исходники)
        and len(рецепт['ресурсы_рендера']) == 7
        and set(рецепт['ресурсы_рендера']) <= set(ресурсы), 'неполные входы или семь шаблонов')
    записи = прочитать_набор(корень, коммит, [*исходники, *ресурсы])
    деревья = {}
    for путь, отпечаток in исходники.items():
        требовать(путь.endswith('.py'), 'AST-рецепт содержит не Python')
        дерево = ast.parse(записи[путь][1], filename=путь)
        требовать(хэш(ast.dump(дерево, include_attributes=False).encode()) == отпечаток,
            'AST изменилась: требуется новый независимый рецепт: ' + путь)
        деревья[путь] = дерево
    # Свежий инвентарь, без seed/первого совпавшего basename.
    индекс = {}; регистр = set()
    for строка in гит(корень, 'ls-tree', '-r', '-z', '--full-tree', коммит).split(b'\0'):
        if not строка: continue
        мета, имя = строка.split(b'\t', 1); путь = имя.decode('utf-8')
        if not (путь.startswith('Инструменты/') and путь.endswith('.py')
            and ('/scripts/' in путь or путь in входы)): continue
        точный_путь(путь)
        режим, тип, объект = мета.decode().split()
        требовать(тип == 'blob' and режим in {'100644', '100755'} and путь.casefold() not in регистр,
            'необычный или неоднозначный исходник свежего инвентаря')
        регистр.add(путь.casefold()); индекс.setdefault(PurePosixPath(путь).stem, []).append(путь)
    коллизии = {}
    for правило in рецепт['импортные_коллизии']:
        требовать(type(правило) is dict and set(правило) == {'владелец', 'имя', 'цель'}, 'неверная коллизия')
        ключ = (правило['владелец'], правило['имя'])
        требовать(ключ not in коллизии, 'повторная коллизия рецепта')
        коллизии[ключ] = правило['цель']
    имена = {}; очередь = list(dict.fromkeys([*входы, *команды])); посещены = set()
    использованные_коллизии = set(); использованные_места = set(); места = []
    def связать(имя, цель):
        требовать(type(имя) is str and имя and '.' not in имя
            and имя not in sys.stdlib_module_names and цель in исходники
            and (имя not in имена or имена[имя] == цель), 'неоднозначный alias рецепта: ' + str(имя))
        имена[имя] = цель
        if цель not in посещены and цель not in очередь: очередь.append(цель)
    for путь in [*входы, *команды]: связать(PurePosixPath(путь).stem, путь)
    for имя, путь in рецепт['дополнительные_имена'].items(): связать(имя, путь)
    def импорт(имя, владелец):
        требовать(type(имя) is str and имя and not имя.startswith('.'), 'неверный импорт')
        if имя.split('.')[0] in sys.stdlib_module_names: return
        требовать('.' not in имя, 'пакетный импорт требует нового контракта')
        кандидаты = индекс.get(имя, [])
        if len(кандидаты) == 1:
            требовать((владелец, имя) not in коллизии, 'устаревшее правило коллизии')
            цель = кандидаты[0]
        else:
            ключ = (владелец, имя); цель = коллизии.get(ключ)
            требовать(цель is not None and цель in кандидаты, 'неизвестный или неоднозначный импорт: ' + имя)
            использованные_коллизии.add(ключ)
        связать(имя, цель)
    эталонные_места = {}
    for место in рецепт['динамика']:
        ключ = (место['путь'], место['область'], место['форма_sha256'])
        требовать(ключ not in эталонные_места, 'неоднозначное AST-место рецепта')
        эталонные_места[ключ] = место
    while очередь:
        путь = очередь.pop(0)
        if путь in посещены: continue
        посещены.add(путь); дерево = деревья[путь]
        адрес_вызова = проверить_обращения_к_загрузчикам(дерево)
        родители = {ребёнок: родитель for родитель in ast.walk(дерево) for ребёнок in ast.iter_child_nodes(родитель)}
        for узел in ast.walk(дерево):
            if isinstance(узел, ast.Import):
                for имя in узел.names: импорт(имя.name, путь)
            elif isinstance(узел, ast.ImportFrom):
                требовать(not узел.level and узел.module, 'относительный импорт требует нового контракта')
                импорт(узел.module, путь)
            elif isinstance(узел, ast.Call):
                адрес = адрес_вызова(узел.func)
                if адрес not in {'importlib.util.spec_from_file_location', 'importlib.import_module',
                    '__import__', 'builtins.__import__', 'compile', 'exec', 'eval',
                    'builtins.compile', 'builtins.exec', 'builtins.eval',
                    'importlib.machinery.SourceFileLoader', 'importlib.machinery.SourcelessFileLoader',
                    'importlib.machinery.ExtensionFileLoader', 'runpy.run_path', 'runpy.run_module'}: continue
                литералы = буквальные_импорты(узел, адрес)
                if литералы is not None:
                    for имя in литералы: импорт(имя, путь)
                    continue
                область = []; предок = родители.get(узел)
                while предок is not None:
                    if isinstance(предок, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)): область.append(предок.name)
                    предок = родители.get(предок)
                область = '.'.join(reversed(область)) or '<module>'
                ключ = (путь, область, форма_места(узел))
                требовать(ключ in эталонные_места and ключ not in использованные_места,
                    'неизвестное или повторное место рецепта')
                использованные_места.add(ключ)
                место = dict(эталонные_места[ключ])
                место.update(исходник_sha256=записи[путь][0]['sha256'], строка=узел.lineno)
                места.append(место)
                for имя, цель in место['цели'].items(): связать(имя, цель)
    требовать(посещены == set(исходники) and использованные_места == set(эталонные_места)
        and использованные_коллизии == set(коллизии), 'неполный или устаревший рецепт')
    места.sort(key=lambda м: (м['путь'], м['строка'], м['форма_sha256']))
    return {'схема': 'fum.закреплённый-профиль-независимого-контура.1',
        'происхождение': {'коммит': коммит, 'дерево': гит(корень, 'rev-parse', коммит + '^{tree}').decode().strip()},
        'рецепт_sha256': хэш(сырые_рецепта),
        'исходники': {п: записи[п][0]['sha256'] for п in sorted(посещены)},
        'ресурсы': [записи[п][0] for п in sorted(ресурсы)], 'ресурсы_рендера': рецепт['ресурсы_рендера'],
        'выбор': {'схема': СХЕМА_ВЫБОРА, 'входы': входы, 'имена': dict(sorted(имена.items())),
            'динамические_места': [{к: з for к, з in м.items() if к in
                {'путь', 'строка', 'форма_sha256', 'цели', 'основание'}} for м in места],
            'ресурсы': ресурсы, 'команды': []}, 'места': места, 'разрешённые_команды': команды}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--корень-кода', required=True)
    разбор.add_argument('--коммит-кода', required=True)
    вход = разбор.add_mutually_exclusive_group(required=True)
    вход.add_argument('--выбор')
    вход.add_argument('--рецепт')
    разбор.add_argument('--sha256', required=True)
    п = разбор.parse_args()
    try:
        сырые = Path(п.рецепт or п.выбор).read_bytes()
        требовать(хэш(сырые) == п.sha256, 'подменён независимый выбор')
        итог = (сгенерировать_кандидат(Path(п.корень_кода), п.коммит_кода, сырые) if п.рецепт else
            построить(Path(п.корень_кода), п.коммит_кода, разобрать(сырые)))
        sys.stdout.buffer.write(байты(итог))
        return 0
    except (ValueError, OSError, subprocess.SubprocessError) as ошибка:
        print(str(ошибка), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(главная())

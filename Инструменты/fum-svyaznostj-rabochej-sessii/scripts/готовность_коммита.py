КОРЕНЬ_СОСТОЯНИЯ = (Path("/Users/Shared") / ("FUM-private-" + str(os.getuid())) if sys.platform == "darwin"
    else Path.home() / ".local/state/FUM") / "готовность-коммитов"


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode()


def путь_этапа(параметры):
    корень = параметры["корень"]
    требовать(isinstance(корень, str) and Path(корень).is_absolute()
        and корень == str(Path(корень).resolve()), "нужно каноническое написание физического корня готовности")
    ключ = [параметры[поле] for поле in ("корень", "ветка", "исходный_коммит", "задача", "запрос")]
    имя = hashlib.sha256(байты(ключ)).hexdigest() + ".json"
    путь = хранение._путь(КОРЕНЬ_СОСТОЯНИЯ / параметры["задача"] / имя)
    требовать(not any(os.path.lexists(предок / ".git") for предок in путь.parents), "готовность должна храниться вне Git")
    return путь


def привязка(параметры):
    if повторная(параметры):
        граница = параметры.get('привязка_повтора')
        import журнал_повторного_состояния_узла as журнал
        журнал.сверить_привязку(параметры, граница)
        прежние = {к: з for к, з in параметры.items() if к not in {'повторный_журнал', 'привязка_повтора'}}
        прежние['схема'] = 'fum.создание-коммита.8'
        return {'создатель': параметры['схема'], 'повтор': граница, 'прежняя': привязка(прежние)}
    if параметры is not None and параметры.get('схема') in {'fum.создание-коммита.9', 'fum.создание-коммита.10'}:
        import связность_независимого_журнала as журнал
        граница = параметры.get('привязка_журнала')
        журнал.сверить_привязку(параметры, граница)
        старые = {к: з for к, з in параметры.items() if к not in {'контракт_журнала', 'привязка_журнала'}}
        старые['схема'] = ('fum.создание-коммита.7' if параметры['схема'] == 'fum.создание-коммита.10'
            else 'fum.создание-коммита.5')
        return {'создатель': параметры['схема'], 'журнал': граница, 'прежняя': привязка(старые)}
    if параметры is not None and параметры.get('схема') in {'fum.создание-коммита.7', 'fum.создание-коммита.8'}:
        поручение = параметры.get('привязка_поручения')
        требовать(параметры.get('режим') == 'контрольная-точка'
            and точный_идентификатор(параметры.get('задача'))
            and точный_идентификатор(параметры.get('исполнитель'))
            and isinstance(поручение, dict)
            and set(поручение) == ({'выбранное_поручение', 'нативное_начало', 'нативное_поручение'} | ({'полномочия_узла'} if параметры.get('схема') == 'fum.создание-коммита.8' else set()))
            and поручение['выбранное_поручение'] == параметры.get('выбранное_поручение'),
            'нет проверенной привязки обычного поручения')
        return {'координатор': параметры['задача'], 'исполнитель': параметры['исполнитель'],
            'поручение': поручение, 'источники': выбор_команд.привязка_источников(параметры['источники'], требовать)}
    if параметры is not None and параметры.get('схема') in {'fum.создание-коммита.5', 'fum.создание-коммита.6'}:
        требовать(параметры.get('режим') == 'контрольная-точка', 'неверный режим ограниченного выбора')
        return выбор_команд.привязка_источников(параметры['источники'], требовать)
    if параметры is not None and параметры.get('схема') == 'fum.создание-коммита.4':
        требовать(параметры.get('режим') == 'дочерний-приём'
            and точный_идентификатор(параметры.get('исполнитель'))
            and all(точный_хэш(параметры.get(к)) for к in ('назначение_sha256', 'основание_sha256')),
            'неверная привязка готовности приёма')
        return {к: параметры[к] for к in ('исполнитель', 'назначение_sha256', 'основание_sha256')}
    if параметры is None or параметры.get('схема') != 'fum.создание-коммита.3':
        return None
    требовать(параметры.get('режим') == 'дочерняя-передача'
        and точный_идентификатор(параметры.get('исполнитель'))
        and точный_хэш(параметры.get('назначение_sha256')), 'неверная привязка дочерней готовности')
    return {ключ: параметры[ключ] for ключ in ('исполнитель', 'назначение_sha256')}


def независимая(параметры):
    return параметры is not None and параметры.get('схема') in {'fum.создание-коммита.9', 'fum.создание-коммита.10'}


def повторная(параметры):
    return параметры is not None and параметры.get('схема') == 'fum.создание-коммита.11'


def с_доказательством(параметры):
    return независимая(параметры) or повторная(параметры)


def ключ_доказательства(параметры):
    return 'доказательство_пары' if повторная(параметры) else 'доказательство_слоя'


def проверить_доказательство(параметры, доказательство):
    if повторная(параметры):
        import журнал_повторного_состояния_узла as журнал
        журнал.сверить_доказательство(параметры, доказательство)
    else:
        import связность_независимого_журнала as журнал
        журнал.сверить_доказательство(доказательство)


def проверить_доказательства(параметры, состояние, доказательства):
    import связность_независимого_журнала as журнал
    требовать(type(доказательства) is list and len(доказательства) == len(состояние['поколения']),
        'неполный список доказательств поколений')
    контекст = (hashlib.sha256(байты(параметры['привязка_повтора'])).hexdigest()
        if повторная(параметры) else журнал.контекст_слоя(параметры))
    отчёт = str(Path(параметры['запрос']).with_name('отчёт.md'))
    for номер, (поколение, запись) in enumerate(zip(состояние['поколения'], доказательства)):
        требовать(type(запись) is dict and set(запись) == {'поколение', 'поколение_sha256', ключ_доказательства(параметры)}
            and type(запись['поколение']) is int and запись['поколение'] == номер
            and запись['поколение_sha256'] == hashlib.sha256(байты(поколение)).hexdigest(),
            'подменён номер или полный снимок поколения')
        проверить_доказательство(параметры, запись[ключ_доказательства(параметры)])
        требовать(запись[ключ_доказательства(параметры)]['контекст_sha256'] == контекст
            and запись[ключ_доказательства(параметры)]['отчёт'] == отчёт, 'чужой исторический контекст или отчёт READY')


def упаковать(параметры, состояние, *, доказательства=None):
    основание = привязка(параметры)
    if с_доказательством(параметры):
        проверить_доказательства(параметры, состояние, доказательства)
        return {'схема': схема_обёртки(параметры), 'привязка': основание,
            'готовность': состояние, 'доказательства_поколений': доказательства}
    требовать(доказательства is None, 'прежняя готовность не принимает новый слой')
    return состояние if основание is None else {
        'схема': схема_обёртки(параметры), 'привязка': основание, 'готовность': состояние}


def схема_обёртки(параметры):
    if повторная(параметры):
        return 'fum.готовность-повторного-эффекта-состояния.1'
    if параметры and параметры.get('схема') in {'fum.создание-коммита.9', 'fum.создание-коммита.10'}:
        return 'fum.готовность-независимой-контрольной-точки.1'
    if параметры and параметры.get('схема') in {'fum.создание-коммита.7', 'fum.создание-коммита.8'}:
        return ('fum.готовность-ветки-состояния-узла.1' if параметры.get('схема') == 'fum.создание-коммита.8' else 'fum.готовность-дочерней-контрольной-точки.1')
    if параметры and параметры.get('схема') == 'fum.создание-коммита.6':
        return 'fum.готовность-команд-с-изображением.1'
    if параметры and параметры.get('схема') == 'fum.создание-коммита.5':
        return 'fum.готовность-выбранных-команд.1'
    return ('fum.готовность-дочернего-приёма.1' if параметры and параметры.get('схема') == 'fum.создание-коммита.4'
        else 'fum.готовность-дочерней-передачи.1')


def проверить_приём(параметры, снимок, замены):
    if параметры and параметры.get('схема') == 'fum.создание-коммита.4':
        требовать(not замены and снимок['проверки'] == [параметры['приём']['основание']['проверка']]
            and снимок['разрешённые_цели'] == параметры['разрешённые_цели'],
            'изменены назначенная проверка или четыре цели готовности приёма')


def прочитать(путь, параметры=None):
    return прочитать_полностью(путь, параметры)[0]


def прочитать_полностью(путь, параметры=None):
    состояние = файлы._разобрать(хранение._прочитать(хранение._путь(путь), приватный=True))
    основание = привязка(параметры)
    доказательства = None
    if isinstance(состояние, dict) and состояние.get('схема') in {
            'fum.готовность-дочерней-передачи.1', 'fum.готовность-дочернего-приёма.1', 'fum.готовность-выбранных-команд.1', 'fum.готовность-команд-с-изображением.1', 'fum.готовность-дочерней-контрольной-точки.1', 'fum.готовность-ветки-состояния-узла.1', 'fum.готовность-независимой-контрольной-точки.1', 'fum.готовность-повторного-эффекта-состояния.1'}:
        поля = {'схема', 'привязка', 'готовность'} | ({'доказательства_поколений'} if с_доказательством(параметры) else set())
        требовать(set(состояние) == поля and основание is not None
            and состояние['схема'] == схема_обёртки(параметры)
            and состояние['привязка'] == основание, 'изменена привязка дочерней готовности')
        доказательства = состояние.get('доказательства_поколений')
        состояние = состояние['готовность']
    else:
        требовать(основание is None, 'прежняя готовность не содержит дочерней привязки')
    поколения.проверить(состояние)
    for поколение in состояние['поколения']:
        проверить_приём(параметры, поколение['снимок'], поколение['замены'])
    if с_доказательством(параметры): проверить_доказательства(параметры, состояние, доказательства)
    return состояние, доказательства


def преобразовать(параметры, действие, *, создать=False, доказательство=None, получить_живое=None):
    ожидаемое = None
    if с_доказательством(параметры):
        требовать(not создать or доказательство is not None, 'новое поколение требует полного доказательства слоя')
        if доказательство is not None:
            проверить_доказательство(параметры, доказательство)
            ожидаемое = json.loads(байты(доказательство))
            требовать(callable(получить_живое), 'нет живой повторной проверки слоя')
    else:
        требовать(доказательство is None and получить_живое is None, 'новый proof не разрешает прежнюю готовность')
    def живое():
        if ожидаемое is not None:
            требовать(получить_живое() == ожидаемое, 'наложение изменилось до эффекта готовности')
    живое()
    путь = путь_этапа(параметры)
    требовать(создать or os.path.lexists(путь), "нет объявленной готовности; сначала вызовите готово")
    if создать:
        путь.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    хранение._путь(путь)
    with файлы._замок(путь):
        прежнее, старые = прочитать_полностью(путь, параметры) if os.path.lexists(путь) else (None, [])
        требовать(прежнее is not None or создать, "готовность исчезла")
        if прежнее is not None:
            требовать(прежнее["корень"] == параметры["корень"], "готовность относится к другому корню")
        предшествующие = (json.loads(байты(прежнее['поколения'])) if прежнее is not None else []) if с_доказательством(параметры) else None
        старые = json.loads(байты(старые)) if с_доказательством(параметры) else None
        новое, результат = действие(прежнее)
        поколения.проверить(новое)
        доказательства = None
        if с_доказательством(параметры):
            требовать(новое['поколения'][:len(предшествующие)] == предшествующие,
                'изменено сохранённое поколение готовности')
            доказательства = json.loads(байты(старые))
            число = len(новое['поколения']) - len(предшествующие)
            требовать(число in {0, 1}, 'неверное число новых поколений')
            if число:
                требовать(ожидаемое is not None, 'нет доказательства нового поколения')
                доказательства.append({'поколение': len(предшествующие),
                    'поколение_sha256': hashlib.sha256(байты(новое['поколения'][-1])).hexdigest(),
                    ключ_доказательства(параметры): ожидаемое})
            elif ожидаемое is not None:
                требовать(доказательства and доказательства[-1][ключ_доказательства(параметры)] == ожидаемое,
                    'готовый слой изменился; нужен отзыв и следующее поколение')
        живое()
        сохраняемое = байты(упаковать(параметры, новое, доказательства=доказательства))
        файлы._установить(путь, сохраняемое)
        return {**результат, "путь": str(путь), "состояние_sha256": hashlib.sha256(сохраняемое).hexdigest()}


def снимок(параметры, команды, необходимые, допуск):
    отпечаток = допуск["содержимое"]
    требовать(isinstance(отпечаток, str) and отпечаток.startswith("sha256:"), "неверный вид отпечатка содержимого")
    return {"задача": параметры["задача"], "ветка": параметры["ветка"], "исходный_коммит": параметры["исходный_коммит"],
        "запрос": параметры["запрос"], "разрешённые_цели": параметры["разрешённые_цели"],
        "экземпляры": [команда["экземпляр"] for команда in команды],
        "отпечаток_содержимого": отпечаток[7:], "проверки": необходимые}


def проверить_постановку(параметры, команды):
    путь = путь_этапа(параметры)
    if not os.path.lexists(путь):
        return
    with файлы._замок(путь):
        состояние = прочитать(путь, параметры)
        прежний = состояние["поколения"][0]["снимок"]
        текущий = снимок(параметры, команды, прежний["проверки"], {"содержимое": "sha256:" + прежний["отпечаток_содержимого"]})
        требовать(состояние["корень"] == параметры["корень"] and поколения.граница(прежний) == поколения.граница(текущий),
            "повторная подготовка расширяет объявленную постановку; новой работе нужен следующий этап")


def объявить(параметры, текущий, записи, предел, замены=None, *, доказательство=None, получить_живое=None):
    проверить_приём(параметры, текущий, замены)
    def действие(прежнее):
        новое = поколения.объявить(параметры["корень"], текущий, записи, time.time_ns(), предел,
                                   прежнее=прежнее, замены=замены)
        return новое, {"схема": "fum.объявленная-готовность-коммита.1", "поколение": новое["активное"],
            "готов_в_наносекундах_эпохи": новое["готов_в_наносекундах_эпохи"],
            "максимальный_возраст": новое["максимальный_возраст"]}
    return преобразовать(параметры, действие, создать=True,
        доказательство=доказательство, получить_живое=получить_живое)


def отозвать(параметры, номер, основание):
    def действие(прежнее):
        новое = поколения.отозвать(прежнее, номер, основание, time.time_ns())
        return новое, {"схема": "fum.отозванная-готовность-коммита.1", "поколение": номер, "фиксировать_этап": False}
    return преобразовать(параметры, действие)


def проверить_доступность(параметры):
    путь = путь_этапа(параметры)
    требовать(os.path.lexists(путь), "нет объявленной готовности; сначала вызовите готово")
    with файлы._замок(путь):
        состояние = прочитать(путь, параметры)
        требовать(состояние["корень"] == параметры["корень"], "готовность относится к другому корню")
        требовать(состояние["активное"] is not None, "готовность отозвана; требуется новое поколение")


def сверить(параметры, текущий, записи, *, доказательство=None, получить_живое=None):
    требовать(not с_доказательством(параметры) or доказательство is not None, 'нет текущего полного proof для фиксации')
    def действие(прежнее):
        поколения.проверить_записи(текущий, записи)
        требовать(прежнее["поколения"][-1]["записи"] == записи,
            "свидетельства проверок изменились после объявления готовности")
        return поколения.оценить(прежнее, текущий, time.time_ns())
    return преобразовать(параметры, действие, доказательство=доказательство, получить_живое=получить_живое)


def активное_доказательство(параметры):
    состояние, доказательства = прочитать_полностью(путь_этапа(параметры), параметры)
    требовать(с_доказательством(параметры) and состояние['активное'] is not None, 'нет активного доказательства слоя')
    return доказательства[состояние['активное']]



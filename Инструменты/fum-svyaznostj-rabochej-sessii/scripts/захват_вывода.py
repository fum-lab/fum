"""Явный локальный захват: исходные каналы сохраняются до представления."""
import base64
import hashlib
import json
import math
import os
from pathlib import Path
import selectors
import signal
import stat
import subprocess
import time
import uuid


def закодировать(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True,
                       separators=(',', ':'), allow_nan=False)+'\n').encode('utf-8')


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def целое(значение, минимум, максимум):
    if type(значение) is not int or not минимум <= значение <= максимум:
        raise ValueError('Недопустимый целочисленный предел')


def записать(дескриптор, данные):
    остаток = memoryview(данные)
    while остаток:
        число = os.write(дескриптор, остаток)
        if число <= 0:
            raise OSError('Запись не продвигается')
        остаток = остаток[число:]


def синхронизировать_каталог(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def сохранить(путь, данные):
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        записать(дескриптор, данные)
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def проверить_каталог(каталог):
    каталог = Path(каталог)
    if not каталог.is_absolute() or каталог != каталог.resolve():
        raise ValueError('Нужен абсолютный физический путь без ссылок')
    if any((родитель/'.git').exists() or (родитель/'.git').is_symlink()
           for родитель in (каталог, *каталог.parents)):
        raise ValueError('Исходные потоки хранятся вне Git')
    return каталог


def остановить(процесс):
    try:
        os.killpg(процесс.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    try:
        процесс.wait(timeout=1)
    except subprocess.TimeoutExpired:
        pass


def захватить(команда, каталог, корень, задача, *, тайм_аут=60,
              предел_байтов=134217728, обработчик='общий'):
    """Совместимый вход для доверенного процесса без конкурентной подмены каталога."""
    return захватить_с_хэшем(команда, каталог, корень, задача, тайм_аут=тайм_аут,
        предел_байтов=предел_байтов, обработчик=обработчик)[0]


def захватить_с_хэшем(команда, каталог, корень, задача, *, тайм_аут=60,
                     предел_байтов=134217728, обработчик='общий'):
    """Возвращает манифест и SHA записанных байтов без повторного чтения.

    Предусловие: доверенный запущенный процесс, единственный писатель приватного
    каталога — этот захват; конкурентной подмены каталога/файлов нет. Проверки
    пути и прав не изолируют процесс с теми же правами. Полнота действительна
    внутри этой кооперативной модели, а защита от враждебного процесса не заявлена.
    """
    каталог = проверить_каталог(каталог)
    if not isinstance(команда, list) or not команда or any(
            not isinstance(слово, str) or '\0' in слово for слово in команда):
        raise ValueError('Нужен непустой список аргументов без NUL')
    if str(uuid.UUID(задача)) != задача:
        raise ValueError('Нужен канонический UUID')
    if type(тайм_аут) not in (int, float) or not math.isfinite(тайм_аут) or not 0 < тайм_аут <= 3600:
        raise ValueError('Недопустимый тайм-аут')
    целое(предел_байтов, 0, 1073741824)
    if обработчик not in ('общий', 'остаток'):
        raise ValueError('Неизвестный обработчик')
    корень = Path(корень).resolve(strict=True)
    if not корень.is_dir():
        raise ValueError('Рабочий корень не является каталогом')
    каталог.mkdir(mode=0o700)
    синхронизировать_каталог(каталог.parent)
    вызов = закодировать({'команда': команда, 'корень': str(корень), 'задача': задача,
        'тайм_аут': тайм_аут, 'предел_байтов': предел_байтов, 'обработчик': обработчик,
        'оболочка': False, 'автоматический_повтор': False})
    сохранить(каталог/'вызов.json', вызов)
    каналы = {имя: {'байты': 0, 'конец': False} for имя in ('stdout', 'stderr')}
    дескрипторы = {}
    процесс = None
    причина = None
    номер = 0
    начало = time.monotonic()
    try:
        for имя in каналы:
            дескрипторы[имя] = os.open(каталог/(имя+'.bin'),
                os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        дескрипторы['наблюдения'] = os.open(каталог/'наблюдения.jsonl',
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        синхронизировать_каталог(каталог)
        try:
            процесс = subprocess.Popen(команда, cwd=корень, stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE, stderr=subprocess.PIPE, shell=False, start_new_session=True)
        except OSError:
            причина = 'отказ-запуска'
        if процесс is not None:
            with selectors.DefaultSelector() as выбор:
                for имя in каналы:
                    поток = getattr(процесс, имя)
                    os.set_blocking(поток.fileno(), False)
                    выбор.register(поток, selectors.EVENT_READ, имя)
                while выбор.get_map() or процесс.poll() is None:
                    осталось = тайм_аут-(time.monotonic()-начало)
                    if осталось <= 0:
                        причина = 'тайм-аут'
                        break
                    for ключ, _ in выбор.select(min(осталось, 0.05)):
                        данные = os.read(ключ.fileobj.fileno(), 65536)
                        имя = ключ.data
                        if not данные:
                            каналы[имя]['конец'] = True
                            выбор.unregister(ключ.fileobj)
                            continue
                        свободно = предел_байтов-sum(канал['байты'] for канал in каналы.values())
                        часть = данные[:свободно]
                        записать(дескрипторы[имя], часть)
                        номер += 1
                        if номер <= 4096:
                            записать(дескрипторы['наблюдения'], закодировать({
                                'номер_наблюдения': номер, 'канал': имя,
                                'смещение': каналы[имя]['байты'], 'сохранено_байтов': len(часть),
                                'прочитано_байтов': len(данные), 'sha256': хэш(часть)}))
                        каналы[имя]['байты'] += len(часть)
                        if len(часть) != len(данные):
                            причина = 'предел-хранения'
                            break
                    if причина:
                        break
            if причина:
                остановить(процесс)
        for дескриптор in дескрипторы.values():
            os.fsync(дескриптор)
    except BaseException:
        if процесс is not None:
            остановить(процесс)
        # Отказ хранилища не получает достоверного конечного манифеста.
        raise
    finally:
        if процесс is not None:
            for имя in каналы:
                getattr(процесс, имя).close()
        for дескриптор in дескрипторы.values():
            os.close(дескриптор)
    for имя, сведения in каналы.items():
        сведения['sha256'] = хэш_файла(каталог/(имя+'.bin'))
    полнота = причина is None and процесс is not None and процесс.returncode is not None and all(
        канал['конец'] for канал in каналы.values())
    результат = {'схема': 'fum.захват-вывода.1', 'задача': задача,
        'вызов_sha256': хэш(вызов), 'каналы': каналы, 'полнота': полнота,
        'код_процесса': процесс.returncode if процесс is not None else None,
        'причина': причина, 'всего_произведено_байтов': sum(
            канал['байты'] for канал in каналы.values()) if полнота else None,
        'наблюдения': {'число': номер, 'sha256': хэш_файла(каталог/'наблюдения.jsonl'),
            'сохранено': min(номер, 4096), 'пропущено': max(номер-4096, 0),
            'порядок': 'порядок-чтения-не-порядок-записи-двух-каналов'},
        'токены': None, 'автоматический_повтор': False,
        'обработчик': {'имя': обработчик, 'состояние': 'не-требуется'}}
    # Исходный манифест фиксируется до производного обработчика.
    сохранить(каталог/'исходный-манифест.json', закодировать(результат))
    синхронизировать_каталог(каталог)
    if обработчик == 'остаток':
        результат['обработчик']['состояние'] = 'не-запущен'
        if полнота and результат['код_процесса'] in (0, 3):
            from детектор_вывода import потребить
            try:
                представление, квитанция = потребить((каталог/'stdout.bin').read_bytes(),
                    каналы['stdout']['sha256'], 16000, результат['код_процесса'])
                сохранить(каталог/'представление.bin', представление)
                сохранить(каталог/'квитанция-обработчика.json', закодировать(квитанция))
                результат['обработчик'].update(состояние='выполнен',
                    sha256=хэш(представление), байты=len(представление))
            except (ValueError, OSError):
                результат['обработчик']['состояние'] = 'отказ'
    данные_манифеста = закодировать(результат)
    сохранить(каталог/'манифест-временный.json', данные_манифеста)
    os.replace(каталог/'манифест-временный.json', каталог/'манифест.json')
    try:
        синхронизировать_каталог(каталог)
    except OSError:
        (каталог/'манифест.json').unlink()
        синхронизировать_каталог(каталог)
        raise
    return результат, хэш(данные_манифеста)


def хэш_файла(путь):
    накопитель = hashlib.sha256()
    with путь.open('rb') as поток:
        while часть := поток.read(65536):
            накопитель.update(часть)
    return накопитель.hexdigest()


def открыть_обычный(путь):
    if not stat.S_ISREG(путь.lstat().st_mode):
        raise ValueError('Нужен обычный файл')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    if not stat.S_ISREG(os.fstat(дескриптор).st_mode):
        os.close(дескриптор)
        raise ValueError('Тип файла изменён')
    return os.fdopen(дескриптор, 'rb')


def проверить_манифест(значение):
    def поля(объект, имена):
        if type(объект) is not dict or set(объект) != set(имена.split()):
            raise ValueError('Неверные поля манифеста')
    def проверить_хэш(строка):
        if type(строка) is not str or len(строка) != 64 or any(знак not in '0123456789abcdef' for знак in строка):
            raise ValueError('Неверный SHA')
    поля(значение, 'схема задача вызов_sha256 каналы полнота код_процесса причина всего_произведено_байтов наблюдения токены автоматический_повтор обработчик')
    if значение['схема'] != 'fum.захват-вывода.1' or type(значение['задача']) is not str or str(uuid.UUID(значение['задача'])) != значение['задача']:
        raise ValueError('Неверная идентичность захвата')
    проверить_хэш(значение['вызов_sha256'])
    if type(значение['полнота']) is not bool or значение['автоматический_повтор'] is not False or значение['токены'] is not None:
        raise ValueError('Неверные признаки захвата')
    код = значение['код_процесса']
    if код is not None:
        целое(код, -255, 255)
    if значение['причина'] not in (None, 'отказ-запуска', 'тайм-аут', 'предел-хранения'):
        raise ValueError('Неверная причина')
    поля(значение['каналы'], 'stdout stderr')
    for сведения in значение['каналы'].values():
        поля(сведения, 'байты конец sha256')
        целое(сведения['байты'], 0, 1073741824)
        проверить_хэш(сведения['sha256'])
        if type(сведения['конец']) is not bool:
            raise ValueError('Неверный конец канала')
    всего = sum(сведения['байты'] for сведения in значение['каналы'].values())
    if значение['полнота']:
        if код is None or значение['причина'] is not None or not all(с['конец'] for с in значение['каналы'].values()) or type(значение['всего_произведено_байтов']) is not int or значение['всего_произведено_байтов'] != всего:
            raise ValueError('Противоречивая полнота')
    elif значение['всего_произведено_байтов'] is not None:
        raise ValueError('Неизвестный объём подменён числом')
    наблюдения = значение['наблюдения']
    поля(наблюдения, 'число sha256 сохранено пропущено порядок')
    проверить_хэш(наблюдения['sha256'])
    for имя in ('число', 'сохранено', 'пропущено'):
        целое(наблюдения[имя], 0, 1073741824)
    if наблюдения['сохранено'] != min(наблюдения['число'], 4096) or наблюдения['пропущено'] != max(наблюдения['число']-4096, 0) or наблюдения['порядок'] != 'порядок-чтения-не-порядок-записи-двух-каналов':
        raise ValueError('Неверная трасса')
    обработчик = значение['обработчик']
    if type(обработчик) is not dict:
        raise ValueError('Неверный обработчик')
    поля(обработчик, 'имя состояние sha256 байты' if обработчик.get('состояние') == 'выполнен' else 'имя состояние')
    if обработчик['имя'] not in ('общий', 'остаток') or обработчик['состояние'] not in ('не-требуется', 'не-запущен', 'выполнен', 'отказ'):
        raise ValueError('Неверное состояние обработчика')
    if обработчик['состояние'] == 'выполнен':
        проверить_хэш(обработчик['sha256'])
        целое(обработчик['байты'], 0, 16000)


def прочитать_манифест(каталог, ожидаемый_хэш):
    каталог = проверить_каталог(каталог)
    путь = каталог/'манифест.json'
    with открыть_обычный(путь) as поток:
        данные = поток.read(65537)
    if len(данные) > 65536:
        raise ValueError('Недопустимый размер манифеста')
    if хэш(данные) != ожидаемый_хэш:
        raise ValueError('SHA манифеста не совпадает')
    def объект(пары):
        результат = {}
        for ключ, значение in пары:
            if ключ in результат:
                raise ValueError('Повтор поля манифеста')
            результат[ключ] = значение
        return результат
    try:
        результат = json.loads(данные, object_pairs_hook=объект)
    except RecursionError as ошибка:
        raise ValueError('Чрезмерная вложенность манифеста') from ошибка
    проверить_манифест(результат)
    return каталог, результат


def уложить(ответ, бюджет):
    целое(бюджет, 100, 1048576)
    данные = закодировать(ответ)
    if len(данные) > бюджет:
        raise ValueError('Представление превышает общий бюджет')
    return данные


def представить_захват(каталог, ожидаемый_хэш, бюджет):
    каталог, манифест = прочитать_манифест(каталог, ожидаемый_хэш)
    ответ = dict(манифест)
    ответ.update(схема='fum.представление-захвата.1',
        модель_доверия='доверенный-процесс-единственный-писатель-без-конкурентной-подмены',
        источник={'манифест': str(каталог/'манифест.json'), 'sha256': ожидаемый_хэш},
        получение_моделью='unknown', состояние_представления='подготовлено',
        область_бюджета='весь-вывод-адаптера-с-LF', единица_бюджета='байты')
    return уложить(ответ, бюджет)


def прочитать_диапазон(каталог, ожидаемый_хэш, канал, начало, число, бюджет):
    каталог, манифест = прочитать_манифест(каталог, ожидаемый_хэш)
    if канал not in ('stdout', 'stderr'):
        raise ValueError('Неизвестный канал')
    целое(начало, 0, 1073741824)
    целое(число, 0, 1048576)
    путь = каталог/(канал+'.bin')
    if путь.is_symlink():
        raise ValueError('Ссылка вместо канала')
    сведения = манифест['каналы'][канал]
    if начало > сведения['байты']:
        raise ValueError('Начало вне сохранённого канала')
    накопитель = hashlib.sha256()
    позиция = 0
    выборка = bytearray()
    with открыть_обычный(путь) as поток:
        while часть := поток.read(min(65536, сведения['байты']-позиция+1)):
            if позиция+len(часть) > сведения['байты']:
                raise ValueError('Размер канала увеличился')
            накопитель.update(часть)
            от = max(начало, позиция)-позиция
            до = min(начало+число, позиция+len(часть))-позиция
            if от < до:
                выборка.extend(часть[от:до])
            позиция += len(часть)
    if позиция != сведения['байты'] or накопитель.hexdigest() != сведения['sha256']:
        raise ValueError('Сохранённый канал изменён')
    конец = начало+len(выборка)
    return уложить({'схема': 'fum.диапазон-захвата.1', 'манифест_sha256': ожидаемый_хэш,
        'канал': канал, 'канал_sha256': сведения['sha256'], 'начало': начало,
        'байты': len(выборка), 'base64': base64.b64encode(выборка).decode('ascii'),
        'следующее_начало': конец if конец < позиция else None,
        'полнота_исходного_захвата': манифест['полнота']}, бюджет)

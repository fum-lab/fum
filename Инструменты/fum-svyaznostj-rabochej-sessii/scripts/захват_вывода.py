КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def закодировать(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True,
                       separators=(',', ':'), allow_nan=False)+'\n').encode('utf-8')


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def целое(значение, минимум, максимум):
    if type(значение) is not int or not минимум <= значение <= максимум:
        raise ValueError('Недопустимый целочисленный предел')


def записать(дескриптор, данные):
    остаток = memoryview(данные)
    while остаток:
        число = os.write(дескриптор, остаток)
        if число <= 0:
            raise OSError('Запись не продвигается')
        остаток = остаток[число:]


def синхронизировать_каталог(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        закрыть_ресурсы([], [дескриптор], sys.exc_info()[0] is not None)


def сохранить(путь, данные):
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        записать(дескриптор, данные)
        os.fsync(дескриптор)
    finally:
        закрыть_ресурсы([], [дескриптор], sys.exc_info()[0] is not None)


def закрыть_ресурсы(потоки, дескрипторы, первичный_отказ):
    ошибка = None
    for действие in [поток.close for поток in потоки] + [
            lambda д=д: os.close(д) for д in дескрипторы]:
        try:
            действие()
        except OSError as причина:
            if ошибка is None:
                ошибка = причина
    if ошибка is not None and not первичный_отказ:
        raise ошибка


def проверить_каталог(каталог):
    каталог = Path(каталог)
    if not каталог.is_absolute() or каталог != каталог.resolve():
        raise ValueError('Нужен абсолютный физический путь без ссылок')
    if any((родитель/'.git').exists() or (родитель/'.git').is_symlink()
           for родитель in (каталог, *каталог.parents)):
        raise ValueError('Исходные потоки хранятся вне Git')
    return каталог


def остановить(процесс):
    try:
        os.killpg(процесс.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    try:
        процесс.wait(timeout=1)
    except subprocess.TimeoutExpired:
        pass


ВЫХОДЫ_ЗАХВАТА = ('вызов.json', 'stdout.bin', 'stderr.bin', 'наблюдения.jsonl',
    'процесс.json', 'исходный-манифест.json', 'представление.bin',
    'квитанция-обработчика.json', 'манифест-временный.json', 'манифест.json')
СУФФИКСЫ_НАБЛЮДАТЕЛЯ = ('stdout', 'stderr', 'process', 'json')


def нормализовать_адрес(значение):
    """Лексическая нормализация не скрывает символьного компонента перед `..`."""
    if not isinstance(значение, (str, Path)) or not str(значение) or '\0' in str(значение):
        raise ValueError('Нужен адрес без NUL')
    путь = Path(значение)
    if not путь.is_absolute():
        raise ValueError('Нужен абсолютный адрес')
    текущий = Path(путь.anchor)
    for часть in путь.parts[1:]:
        текущий /= часть
        if текущий.is_symlink():
            raise ValueError('Символьный компонент адреса')
    return Path(os.path.abspath(путь))


def ключ_адреса(путь):
    # Консервативный запрет алиасов, а не определение семантики данного тома.
    return tuple(unicodedata.normalize('NFC', часть).casefold() for часть in путь.parts)


def составить_план_выходов(каталог, предметные_цели=(), префикс=None, *, проверить_отсутствие=True):
    """Полный упорядоченный план; функция не создаёт и не открывает выходы."""
    каталог = проверить_каталог(нормализовать_адрес(каталог))
    if type(предметные_цели) not in (list, tuple) or len(предметные_цели) > 4096:
        raise ValueError('Нужен конечный список предметных целей')
    for цель in предметные_цели:
        if type(цель) is dict and type(цель.get('роль')) is str and цель['роль'].startswith(('захват:', 'наблюдатель:')):
            raise ValueError('Предметная роль занимает служебное пространство')
    план = [{'роль': 'захват:каталог', 'путь': str(каталог), 'режим': 0o700}]
    план += [{'роль': 'захват:'+имя, 'путь': str(каталог/имя), 'режим': 0o600}
             for имя in ВЫХОДЫ_ЗАХВАТА]
    if префикс is not None:
        префикс = проверить_каталог(нормализовать_адрес(префикс))
        план += [{'роль': 'наблюдатель:'+имя, 'путь': str(префикс)+'.'+имя,
                  'режим': 0o600} for имя in СУФФИКСЫ_НАБЛЮДАТЕЛЯ]
    план += [dict(цель) if type(цель) is dict else цель for цель in предметные_цели]
    роли, адреса = set(), {}
    for цель in план:
        if type(цель) is not dict or set(цель) != {'роль', 'путь', 'режим'}:
            raise ValueError('Неверные поля цели')
        роль = цель['роль']
        if type(роль) is not str or not роль or '\0' in роль or роль in роли:
            raise ValueError('Пустая или повторная роль')
        роли.add(роль)
        if type(цель['режим']) is not int or цель['режим'] not in (0o400, 0o600, 0o700):
            raise ValueError('Неверный режим цели')
        if роль != 'захват:каталог' and цель['режим'] == 0o700:
            raise ValueError('Файлу требуется режим 0400 или 0600')
        путь = нормализовать_адрес(цель['путь'])
        цель['путь'] = str(путь)
        ключ = ключ_адреса(путь)
        if ключ in адреса:
            raise ValueError('Повтор адреса или Unicode/casefold алиас')
        адреса[ключ] = роль
        if проверить_отсутствие and (путь.exists() or путь.is_symlink()):
            raise FileExistsError('Выход уже существует: '+str(путь))
        if роль.startswith('захват:') and роль != 'захват:каталог':
            continue
        if проверить_отсутствие and (not путь.parent.is_dir() or not os.access(путь.parent, os.W_OK | os.X_OK)):
            raise ValueError('Родитель выхода отсутствует или недоступен')
    for ключ, роль in адреса.items():
        for длина in range(1, len(ключ)):
            предок = адреса.get(ключ[:длина])
            if предок is not None and not (предок == 'захват:каталог' and
                    роль.startswith('захват:') and len(ключ) == длина+1):
                raise ValueError('Пересекающиеся области выходов')
    return план


def захватить(команда, каталог, корень, задача, *, тайм_аут=60,
              предел_байтов=134217728, обработчик='общий', предметные_цели=None,
              префикс_наблюдателя=None):
    """Совместимый вход для доверенного процесса без конкурентной подмены каталога."""
    return захватить_с_хэшем(команда, каталог, корень, задача, тайм_аут=тайм_аут,
        предел_байтов=предел_байтов, обработчик=обработчик,
        предметные_цели=предметные_цели, префикс_наблюдателя=префикс_наблюдателя)[0]


def захватить_с_хэшем(команда, каталог, корень, задача, *, тайм_аут=60,
                     предел_байтов=134217728, обработчик='общий',
                     предметные_цели=None, префикс_наблюдателя=None):
    """Возвращает манифест и SHA записанных байтов без повторного чтения.

    Предусловие: доверенный запущенный процесс, единственный писатель приватного
    каталога — этот захват; конкурентной подмены каталога/файлов нет. Проверки
    пути и прав не изолируют процесс с теми же правами. Полнота действительна
    внутри этой кооперативной модели, а защита от враждебного процесса не заявлена.
    """
    начало_подготовки = time.monotonic_ns()
    каталог = проверить_каталог(каталог)
    if not isinstance(команда, list) or not команда or any(
            not isinstance(слово, str) or '\0' in слово for слово in команда):
        raise ValueError('Нужен непустой список аргументов без NUL')
    if str(uuid.UUID(задача)) != задача:
        raise ValueError('Нужен канонический UUID')
    if type(тайм_аут) not in (int, float) or not math.isfinite(тайм_аут) or not 0 < тайм_аут <= 3600:
        raise ValueError('Недопустимый тайм-аут')
    целое(предел_байтов, 0, 1073741824)
    if обработчик not in ('общий', 'остаток'):
        raise ValueError('Неизвестный обработчик')
    корень = Path(корень).resolve(strict=True)
    if not корень.is_dir():
        raise ValueError('Рабочий корень не является каталогом')
    план = составить_план_выходов(каталог,
        () if предметные_цели is None else предметные_цели, префикс_наблюдателя)
    опт = предметные_цели is not None or префикс_наблюдателя is not None
    вызов = {'команда': команда, 'корень': str(корень), 'задача': задача,
        'тайм_аут': тайм_аут, 'предел_байтов': предел_байтов, 'обработчик': обработчик,
        'оболочка': False, 'автоматический_повтор': False}
    if опт:
        вызов['план'] = {'схема': 'fum.план-выходов-захвата.1', 'цели': план}
    вызов = закодировать(вызов)
    if опт and len(вызов) > 1048576:
        raise ValueError('Чрезмерный план или вызов')
    интервалы = {'подготовка_начата_нс': начало_подготовки,
        'план_проверен_нс': time.monotonic_ns()}
    экспорты = {}
    try:
        # Все четыре имени резервируются до единственного Popen. Открытые FD
        # сохраняются до конца: метаданные не создаются повторным O_EXCL.
        for цель in план:
            if цель['роль'].startswith('наблюдатель:'):
                имя = цель['роль'].split(':', 1)[1]
                экспорты[имя] = os.open(цель['путь'],
                    os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        return _захватить_в_каталог(команда, каталог, корень, задача, тайм_аут,
            предел_байтов, обработчик, вызов, опт, интервалы, экспорты, план)
    finally:
        закрыть_ресурсы([], экспорты.values(), sys.exc_info()[0] is not None)


def _захватить_в_каталог(команда, каталог, корень, задача, тайм_аут,
                       предел_байтов, обработчик, вызов, опт, интервалы, экспорты, план):
    каталог.mkdir(mode=0o700)
    синхронизировать_каталог(каталог.parent)
    сохранить(каталог/'вызов.json', вызов)
    каналы = {имя: {'байты': 0, 'конец': False} for имя in ('stdout', 'stderr')}
    дескрипторы = {}
    процесс = None
    причина = None
    номер = 0
    начало = time.monotonic()
    try:
        for имя in каналы:
            дескрипторы[имя] = os.open(каталог/(имя+'.bin'),
                os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        дескрипторы['наблюдения'] = os.open(каталог/'наблюдения.jsonl',
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        синхронизировать_каталог(каталог)
        интервалы.update(pid=None, pid_наблюдателя=os.getpid(),
            перед_запуском_нс=time.monotonic_ns(), после_запуска_нс=None)
        эпоха_начала = time.time_ns()
        try:
            процесс = subprocess.Popen(команда, cwd=корень, stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE, stderr=subprocess.PIPE, shell=False, start_new_session=True)
        except OSError:
            причина = 'отказ-запуска'
        if процесс is not None:
            интервалы.update(pid=процесс.pid, после_запуска_нс=time.monotonic_ns())
            if опт:
                сохранить(каталог/'процесс.json', закодировать(интервалы))
                if экспорты:
                    записать(экспорты['process'], закодировать({'argv': команда,
                        'cwd': str(корень), 'pid': процесс.pid,
                        'observer_pid': os.getpid(), 'start_epoch_ns': эпоха_начала}))
                    os.fsync(экспорты['process'])
                синхронизировать_каталог(каталог)
            with selectors.DefaultSelector() as выбор:
                for имя in каналы:
                    поток = getattr(процесс, имя)
                    os.set_blocking(поток.fileno(), False)
                    выбор.register(поток, selectors.EVENT_READ, имя)
                while выбор.get_map() or процесс.poll() is None:
                    осталось = тайм_аут-(time.monotonic()-начало)
                    if осталось <= 0:
                        причина = 'тайм-аут'
                        break
                    for ключ, _ in выбор.select(min(осталось, 0.05)):
                        данные = os.read(ключ.fileobj.fileno(), 65536)
                        имя = ключ.data
                        if not данные:
                            каналы[имя]['конец'] = True
                            выбор.unregister(ключ.fileobj)
                            continue
                        свободно = предел_байтов-sum(канал['байты'] for канал in каналы.values())
                        часть = данные[:свободно]
                        записать(дескрипторы[имя], часть)
                        if экспорты:
                            записать(экспорты[имя], часть)
                        номер += 1
                        if номер <= 4096:
                            записать(дескрипторы['наблюдения'], закодировать({
                                'номер_наблюдения': номер, 'канал': имя,
                                'смещение': каналы[имя]['байты'], 'сохранено_байтов': len(часть),
                                'прочитано_байтов': len(данные), 'sha256': хэш(часть)}))
                        каналы[имя]['байты'] += len(часть)
                        if len(часть) != len(данные):
                            причина = 'предел-хранения'
                            break
                    if причина:
                        break
            if причина:
                остановить(процесс)
        интервалы['процесс_и_потоки_завершены_нс'] = time.monotonic_ns()
        for дескриптор in дескрипторы.values():
            os.fsync(дескриптор)
        for дескриптор in экспорты.values():
            os.fsync(дескриптор)
    except BaseException:
        if процесс is not None:
            try:
                остановить(процесс)
            except OSError:
                pass
        # Отказ хранилища не получает достоверного конечного манифеста.
        raise
    finally:
        закрыть_ресурсы([getattr(процесс, имя) for имя in каналы] if процесс is not None else [],
            дескрипторы.values(), sys.exc_info()[0] is not None)
    for имя, сведения in каналы.items():
        сведения['sha256'] = хэш_файла(каталог/(имя+'.bin'))
    полнота = причина is None and процесс is not None and процесс.returncode is not None and all(
        канал['конец'] for канал in каналы.values())
    результат = {'схема': 'fum.захват-вывода.2' if опт else 'fum.захват-вывода.1', 'задача': задача,
        'вызов_sha256': хэш(вызов), 'каналы': каналы, 'полнота': полнота,
        'код_процесса': процесс.returncode if процесс is not None else None,
        'причина': причина, 'всего_произведено_байтов': sum(
            канал['байты'] for канал in каналы.values()) if полнота else None,
        'наблюдения': {'число': номер, 'sha256': хэш_файла(каталог/'наблюдения.jsonl'),
            'сохранено': min(номер, 4096), 'пропущено': max(номер-4096, 0),
            'порядок': 'порядок-чтения-не-порядок-записи-двух-каналов'},
        'токены': None, 'автоматический_повтор': False,
        'обработчик': {'имя': обработчик, 'состояние': 'не-требуется'}}
    if опт:
        результат.update(процесс=dict(интервалы), экспорт=None)
    # Исходный манифест фиксируется до производного обработчика.
    сохранить(каталог/'исходный-манифест.json', закодировать(результат))
    синхронизировать_каталог(каталог)
    if обработчик == 'остаток':
        результат['обработчик']['состояние'] = 'не-запущен'
        if полнота and результат['код_процесса'] in (0, 3):
            from детектор_вывода import потребить
            try:
                представление, квитанция = потребить((каталог/'stdout.bin').read_bytes(),
                    каналы['stdout']['sha256'], 16000, результат['код_процесса'])
                сохранить(каталог/'представление.bin', представление)
                сохранить(каталог/'квитанция-обработчика.json', закодировать(квитанция))
                результат['обработчик'].update(состояние='выполнен',
                    sha256=хэш(представление), байты=len(представление))
            except (ValueError, OSError):
                результат['обработчик']['состояние'] = 'отказ'
    if опт:
        if экспорты:
            записать(экспорты['json'], закодировать({'код': результат['код_процесса'],
                'монотонные_нс': интервалы['процесс_и_потоки_завершены_нс']-интервалы['перед_запуском_нс'],
                'stdout_sha256': каналы['stdout']['sha256'], 'stdout_байты': каналы['stdout']['байты'],
                'stderr_sha256': каналы['stderr']['sha256'], 'stderr_байты': каналы['stderr']['байты'],
                'pid': интервалы['pid'], 'observer_pid': os.getpid()}))
            for дескриптор in экспорты.values():
                os.fsync(дескриптор)
            пути = {цель['роль'].split(':', 1)[1]: Path(цель['путь']) for цель in план
                if цель['роль'].startswith('наблюдатель:')}
            for родитель in {путь.parent for путь in пути.values()}:
                синхронизировать_каталог(родитель)
            результат['экспорт'] = {имя: {'байты': путь.stat().st_size,
                'sha256': хэш_файла(путь)} for имя, путь in пути.items()}
        результат['процесс']['перед_финальной_записью_нс'] = time.monotonic_ns()
    данные_манифеста = закодировать(результат)
    сохранить(каталог/'манифест-временный.json', данные_манифеста)
    os.replace(каталог/'манифест-временный.json', каталог/'манифест.json')
    try:
        синхронизировать_каталог(каталог)
    except OSError:
        (каталог/'манифест.json').unlink()
        синхронизировать_каталог(каталог)
        raise
    return результат, хэш(данные_манифеста)


def хэш_файла(путь):
    накопитель = hashlib.sha256()
    with путь.open('rb') as поток:
        while часть := поток.read(65536):
            накопитель.update(часть)
    return накопитель.hexdigest()


def открыть_обычный(путь):
    if not stat.S_ISREG(путь.lstat().st_mode):
        raise ValueError('Нужен обычный файл')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    if not stat.S_ISREG(os.fstat(дескриптор).st_mode):
        os.close(дескриптор)
        raise ValueError('Тип файла изменён')
    return os.fdopen(дескриптор, 'rb')


def проверить_манифест(значение):
    def поля(объект, имена):
        if type(объект) is not dict or set(объект) != set(имена.split()):
            raise ValueError('Неверные поля манифеста')
    def проверить_хэш(строка):
        if type(строка) is not str or len(строка) != 64 or any(знак not in '0123456789abcdef' for знак in строка):
            raise ValueError('Неверный SHA')
    if type(значение) is dict and значение.get('схема') == 'fum.захват-вывода.2':
        прежнее = {ключ: поле for ключ, поле in значение.items() if ключ not in ('процесс', 'экспорт')}
        прежнее['схема'] = 'fum.захват-вывода.1'
        проверить_манифест(прежнее)
        if 'процесс' not in значение or 'экспорт' not in значение:
            raise ValueError('Неполная вторая схема')
        процесс = значение['процесс']
        поля(процесс, 'pid pid_наблюдателя подготовка_начата_нс план_проверен_нс перед_запуском_нс после_запуска_нс процесс_и_потоки_завершены_нс перед_финальной_записью_нс')
        целое(процесс['pid_наблюдателя'], 1, 2**63-1)
        предыдущая = 0
        for ключ in ('подготовка_начата_нс', 'план_проверен_нс', 'перед_запуском_нс',
                     'после_запуска_нс', 'процесс_и_потоки_завершены_нс', 'перед_финальной_записью_нс'):
            время = процесс[ключ]
            if ключ == 'после_запуска_нс' and процесс['pid'] is None and время is None:
                continue
            целое(время, предыдущая, 2**63-1)
            предыдущая = время
        if процесс['pid'] is None:
            if значение['причина'] != 'отказ-запуска' or значение['код_процесса'] is not None:
                raise ValueError('Неизвестный PID противоречит исходу')
        else:
            целое(процесс['pid'], 1, 2**63-1)
        экспорт = значение['экспорт']
        if экспорт is not None:
            поля(экспорт, 'stdout stderr process json')
            for имя, сведения in экспорт.items():
                поля(сведения, 'байты sha256')
                целое(сведения['байты'], 0, 1073741824)
                проверить_хэш(сведения['sha256'])
                if имя in ('stdout', 'stderr') and any(
                        сведения[ключ] != значение['каналы'][имя][ключ] for ключ in ('байты', 'sha256')):
                    raise ValueError('Экспорт канала расходится с захватом')
        return
    поля(значение, 'схема задача вызов_sha256 каналы полнота код_процесса причина всего_произведено_байтов наблюдения токены автоматический_повтор обработчик')
    if значение['схема'] != 'fum.захват-вывода.1' or type(значение['задача']) is not str or str(uuid.UUID(значение['задача'])) != значение['задача']:
        raise ValueError('Неверная идентичность захвата')
    проверить_хэш(значение['вызов_sha256'])
    if type(значение['полнота']) is not bool or значение['автоматический_повтор'] is not False or значение['токены'] is not None:
        raise ValueError('Неверные признаки захвата')
    код = значение['код_процесса']
    if код is not None:
        целое(код, -255, 255)
    if значение['причина'] not in (None, 'отказ-запуска', 'тайм-аут', 'предел-хранения'):
        raise ValueError('Неверная причина')
    поля(значение['каналы'], 'stdout stderr')
    for сведения in значение['каналы'].values():
        поля(сведения, 'байты конец sha256')
        целое(сведения['байты'], 0, 1073741824)
        проверить_хэш(сведения['sha256'])
        if type(сведения['конец']) is not bool:
            raise ValueError('Неверный конец канала')
    всего = sum(сведения['байты'] for сведения in значение['каналы'].values())
    if значение['полнота']:
        if код is None or значение['причина'] is not None or not all(с['конец'] for с in значение['каналы'].values()) or type(значение['всего_произведено_байтов']) is not int or значение['всего_произведено_байтов'] != всего:
            raise ValueError('Противоречивая полнота')
    elif значение['всего_произведено_байтов'] is not None:
        raise ValueError('Неизвестный объём подменён числом')
    наблюдения = значение['наблюдения']
    поля(наблюдения, 'число sha256 сохранено пропущено порядок')
    проверить_хэш(наблюдения['sha256'])
    for имя in ('число', 'сохранено', 'пропущено'):
        целое(наблюдения[имя], 0, 1073741824)
    if наблюдения['сохранено'] != min(наблюдения['число'], 4096) or наблюдения['пропущено'] != max(наблюдения['число']-4096, 0) or наблюдения['порядок'] != 'порядок-чтения-не-порядок-записи-двух-каналов':
        raise ValueError('Неверная трасса')
    обработчик = значение['обработчик']
    if type(обработчик) is not dict:
        raise ValueError('Неверный обработчик')
    поля(обработчик, 'имя состояние sha256 байты' if обработчик.get('состояние') == 'выполнен' else 'имя состояние')
    if обработчик['имя'] not in ('общий', 'остаток') or обработчик['состояние'] not in ('не-требуется', 'не-запущен', 'выполнен', 'отказ'):
        raise ValueError('Неверное состояние обработчика')
    if обработчик['состояние'] == 'выполнен':
        проверить_хэш(обработчик['sha256'])
        целое(обработчик['байты'], 0, 16000)


def прочитать_манифест(каталог, ожидаемый_хэш):
    каталог = проверить_каталог(каталог)
    путь = каталог/'манифест.json'
    with открыть_обычный(путь) as поток:
        данные = поток.read(65537)
    if len(данные) > 65536:
        raise ValueError('Недопустимый размер манифеста')
    if хэш(данные) != ожидаемый_хэш:
        raise ValueError('SHA манифеста не совпадает')
    def объект(пары):
        результат = {}
        for ключ, значение in пары:
            if ключ in результат:
                raise ValueError('Повтор поля манифеста')
            результат[ключ] = значение
        return результат
    try:
        результат = json.loads(данные, object_pairs_hook=объект)
    except RecursionError as ошибка:
        raise ValueError('Чрезмерная вложенность манифеста') from ошибка
    проверить_манифест(результат)
    if результат['схема'] == 'fum.захват-вывода.2':
        _проверить_свидетельства_второй_схемы(каталог, результат)
    return каталог, результат


def разобрать_JSON(данные):
    def объект(пары):
        результат = {}
        for ключ, значение in пары:
            if ключ in результат:
                raise ValueError('Повтор поля JSON')
            результат[ключ] = значение
        return результат
    try:
        return json.loads(данные, object_pairs_hook=объект,
            parse_constant=lambda _: (_ for _ in ()).throw(ValueError('Недопустимая константа')))
    except RecursionError as ошибка:
        raise ValueError('Чрезмерная вложенность JSON') from ошибка


def _прочитать_документ(путь, предел=1048576):
    with открыть_обычный(путь) as поток:
        данные = поток.read(предел+1)
    if len(данные) > предел:
        raise ValueError('Чрезмерный документ')
    return данные, разобрать_JSON(данные)


def свидетельство_файла(путь):
    """Читает только наблюдённый размер; растущий поток не ждёт EOF."""
    ответ = {'путь': str(путь), 'состояние': 'отсутствует', 'байты': None, 'sha256': None}
    try:
        путь = нормализовать_адрес(путь)
        with открыть_обычный(путь) as поток:
            до = os.fstat(поток.fileno())
            остаток = до.st_size
            накопитель = hashlib.sha256()
            while остаток:
                часть = поток.read(min(65536, остаток))
                if not часть:
                    raise ValueError('Файл усечён во время чтения')
                накопитель.update(часть)
                остаток -= len(часть)
            после = os.fstat(поток.fileno())
            метка = lambda с: (с.st_dev, с.st_ino, с.st_size, с.st_mtime_ns, с.st_ctime_ns)
            if метка(до) != метка(после) or метка(после) != метка(путь.lstat()):
                raise ValueError('Файл изменился во время чтения')
            ответ.update(состояние='обычный', байты=до.st_size, sha256=накопитель.hexdigest())
    except FileNotFoundError:
        pass
    except (OSError, ValueError):
        ответ['состояние'] = 'недостоверен'
    return ответ


def _проверить_свидетельства_второй_схемы(каталог, манифест):
    байты, вызов = _прочитать_документ(каталог/'вызов.json')

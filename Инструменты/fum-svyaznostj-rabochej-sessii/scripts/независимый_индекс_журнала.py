"""Чистое представление переданного замкнутого состава, без приёмки."""
from urllib.parse import quote
import контракт_независимого_журнала as контракт


def построить_индекс(состав, файлы, *, ожидаемый_sha256):
    контракт.поля(состав, {'схема', 'записи'})
    версии = {'fum.состав-независимого-журнала.1': 1, 'fum.состав-независимого-журнала.2': 2,
        'fum.состав-независимого-журнала.3': 3}
    контракт.требовать(состав['схема'] in версии, 'неизвестная схема состава')
    версия = версии[состав['схема']]
    одиночный = 'fum.исторический-одиночный-запрос-журнала.1'
    форматы = {'fum.прежняя-пара-журнала.1', 'fum.независимая-пара-журнала.1'}
    if версия >= 2:
        форматы.add(одиночный)
    if версия == 3:
        форматы.add('fum.обычная-независимая-пара-журнала.1')
    записи = состав['записи']
    контракт.требовать(type(записи) is list and 1 <= len(записи) <= 16384, 'неверный конечный состав')
    контракт.требовать(type(файлы) is dict, 'нужны фактические байты всех пар')
    идентичности = set(); имена = set(); пути = {}; время = []
    for запись in записи:
        контракт.поля(запись, {'идентификатор', 'формат', 'журнал', 'заголовок', 'файлы', 'приёмка'})
        контракт.отпечаток(запись['идентификатор'])
        контракт.требовать(запись['идентификатор'] not in идентичности, 'повтор ID записи')
        идентичности.add(запись['идентификатор'])
        контракт.требовать(запись['формат'] in форматы, 'неизвестное поколение записи')
        время.append(контракт.имя_журнала(запись['журнал'],
            прежнее=запись['формат'] != 'fum.независимая-пара-журнала.1'))
        контракт.строка(запись['заголовок'])
        ключ = контракт.ключ_коллизии(запись['журнал'])
        контракт.требовать(ключ not in имена, 'коллизия имени записи'); имена.add(ключ)
        контракт.селектор(запись['приёмка'])
        части = ('запрос.md',) if запись['формат'] == одиночный else ('запрос.md', 'отчёт.md')
        контракт.требовать(type(запись['файлы']) is list and len(запись['файлы']) == len(части), 'нужен точный состав записи')
        for файл, имя in zip(запись['файлы'], части):
            контракт.поля(файл, {'путь', 'sha256', 'режим'})
            контракт.требовать(файл['путь'] == 'Журнал/' + запись['журнал'] + '/' + имя
                and type(файл['режим']) is int and файл['режим'] == 0o644, 'подмена пути или режима пары')
            контракт.отпечаток(файл['sha256']); пути[файл['путь']] = файл['sha256']
    упорядоченные = sorted(записи, key=lambda з: з['журнал'])
    канонический_состав = контракт.канон({**состав, 'записи': упорядоченные})
    контракт.отпечаток(ожидаемый_sha256)
    контракт.требовать(контракт.хэш(канонический_состав) == ожидаемый_sha256, 'подмена или устаревание состава')
    контракт.требовать(set(файлы) == set(пути), 'пропущенные или лишние файлы состава')
    for имя, байты in файлы.items():
        контракт.требовать(type(байты) is bytes and 0 < len(байты) <= контракт.ПРЕДЕЛ_ПАРЫ
            and контракт.хэш(байты) == пути[имя], 'подмена байтов пары')
    def ссылка(запись, часть='запрос.md'):
        return '[перейти](../Журнал/' + quote(запись['журнал'], safe='') + '/' + quote(часть, safe='') + ')'
    содержание = ('# Навигация Журнала\n\n<!-- FUM-ИНДЕКС-ЖУРНАЛА: ' + str(версия) + ' -->\n'
        + 'Состав поколения: `sha256:' + ожидаемый_sha256 + '`.\n\n'
        + '| Этап | Запрос | Отчёт | Предыдущий | Следующий |\n| --- | --- | --- | --- | --- |\n')
    строки = []
    for номер, запись in enumerate(упорядоченные):
        предыдущий = ссылка(упорядоченные[номер - 1]) if номер else '—'
        следующий = ссылка(упорядоченные[номер + 1]) if номер + 1 < len(упорядоченные) else '—'
        отчёт = ('Историческая запись без отдельного отчёта'
            if запись['формат'] == одиночный else ссылка(запись, 'отчёт.md'))
        строки.append('| ' + контракт.надпись(запись['заголовок']) + ' | ' + ссылка(запись)
            + ' | ' + отчёт + ' | ' + предыдущий + ' | ' + следующий + ' |\n')
    байты = контракт.свежесть(содержание + ''.join(строки), max(время))
    return {'путь': 'Индексы/навигация-журнала.md', 'байты': байты, 'sha256': контракт.хэш(байты),
        'состав_sha256': ожидаемый_sha256, 'записей': len(записи), 'разрешение_установки': False}

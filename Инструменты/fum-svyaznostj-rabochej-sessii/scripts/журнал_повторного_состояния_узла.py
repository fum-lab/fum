def _содержимое_без_свежести(данные, *, путь=None, корень=None):
    текст = данные.decode('utf-8')
    if путь is not None:
        from связность_независимого_журнала import модуль_свежести
        свежесть = модуль_свежести()
        тело, метаданные, повреждение = свежесть.split_recency_block(текст, путь=путь, корень=корень)
        тело = свежесть.canonical_content(тело)
        стабильное, повреждённый_блок = свежесть.стабильное_содержание_отчёта(путь, корень, тело)
        требовать(not повреждение and not повреждённый_блок and метаданные is not None
            and метаданные.digest in {свежесть.content_digest(тело), свежесть.content_digest(стабильное)},
            'неверная каноническая recency пары')
        return тело
    образец = re.compile(r'\n<!-- FUM-MD-RECENCY:BEGIN -->\n'
        r'<!-- last-content-edit: ([0-9-]{10} [0-9:]{8} MSK) -->\n'
        r'<!-- content-sha256: sha256:[0-9a-f]{64} -->\n<!-- FUM-MD-RECENCY:END -->\n\Z')
    совпадение = образец.search(текст)
    требовать(совпадение is not None, 'нет точной recency пары')
    тело = текст[:совпадение.start()]
    требовать(контракт.свежесть(тело, совпадение[1]) == данные, 'неверная recency пары')
    return тело


def _неизменяемое_тело(данные, *, путь=None, корень=None):
    тело = _содержимое_без_свежести(данные, путь=путь, корень=корень)
    требовать(тело.count(НАЧАЛО) == тело.count(КОНЕЦ) == 1, 'неоднозначная рабочая область P.2')
    начало = тело.index(НАЧАЛО) + len(НАЧАЛО)
    конец = тело.index(КОНЕЦ)
    требовать(начало < конец, 'переставлены маркеры рабочей области')
    тело = тело[:начало] + тело[конец:]
    образец = re.compile(r'(?m)^<!-- FUM-CHECK-RUNS:BEGIN [^\n]+ -->\n.*?^<!-- FUM-CHECK-RUNS:END -->', re.S)
    требовать(тело.count('<!-- FUM-CHECK-RUNS:BEGIN') == тело.count('<!-- FUM-CHECK-RUNS:END -->') == 1,
        'неоднозначный блок прямых запусков')
    тело, число = образец.subn('<!-- FUM-CHECK-RUNS:управляемая-область -->', тело)
    требовать(число == 1, 'неверная граница прямых запусков')
    return тело


def _сверить_пару(корень, план, квитанция):
    контракт.поля(квитанция, {'схема', 'привязка', 'папка', 'файлы'})
    требовать(квитанция['схема'] == 'fum.квитанция-повторного-журнала.1'
        and type(квитанция['файлы']) is list and len(квитанция['файлы']) == 2,
        'неверная квитанция пары')
    папка = _точный_путь(корень, str(Path(план['файлы'][0]['путь']).parent))
    состояние_папки = папка.lstat()
    требовать(_метка(состояние_папки) == квитанция['папка'] and stat.S_ISDIR(состояние_папки.st_mode)
        and stat.S_IMODE(состояние_папки.st_mode) == 0o755 and состояние_папки.st_uid == os.getuid(),
        'папка пары заменена либо изменены её владелец или режим')
    for исходный, запись in zip(план['файлы'], квитанция['файлы'], strict=True):
        контракт.поля(запись, {'путь', 'sha256', 'режим', 'устройство', 'номер_файла'})
        требовать({к: запись[к] for к in ('путь', 'sha256', 'режим')} ==
            {к: исходный[к] for к in ('путь', 'sha256', 'режим')}, 'подменён состав квитанции пары')
        адрес = _точный_путь(корень, исходный['путь'])
        данные, метка = _прочитать(адрес)
        if адрес.name == 'запрос.md':
            требовать(_метка(метка) == {к: запись[к] for к in ('устройство', 'номер_файла')}, 'файл запроса заменён')
            требовать(данные == исходный['текст'].encode(), 'изменён исходный запрос P.2')
        else:
            # RAW-preview и recency законно заменяют отчёт атомарно. Его
            # актуальные bytes/stat закрепляются отдельно в proof READY.
            требовать(_неизменяемое_тело(данные, путь=адрес, корень=корень) ==
                _неизменяемое_тело(исходный['текст'].encode(), путь=адрес, корень=корень),
                'отчёт изменён вне разрешённых рабочих областей')


def _прочитать_квитанцию(корень, план, привязка, каталог):
    _проверить_эпизод(корень, план, привязка, каталог)
    намерение = каталог / 'намерение.json'
    квитанция = каталог / 'квитанция.json'
    требовать(намерение.exists() and квитанция.exists(), 'незавершённое намерение пары; исход неизвестен')
    сырые_намерения, _ = _прочитать(намерение, приватный=True)
    требовать(сырые_намерения == байты(привязка), 'чужое намерение установки пары')
    сырые, _ = _прочитать(квитанция, приватный=True)
    документ = разобрать(сырые)
    требовать(сырые == байты(документ) and документ['привязка'] == привязка, 'подменена квитанция пары')
    _сверить_пару(корень, план, документ)
    return {'схема': 'fum.привязка-повторного-журнала.1', 'цепь': привязка,
        'квитанция': {'путь': str(квитанция), 'sha256': контракт.хэш(сырые)}, 'документ': документ}



def рабочая_область(параметры, план):
    """Заголовок JSON и настоящий Markdown находятся внутри области P.2."""
    корень = Path(параметры['корень'])
    адрес = корень / план['файлы'][1]['путь']
    тело = _содержимое_без_свежести(_прочитать(адрес)[0], путь=адрес, корень=корень)
    требовать(тело.count(НАЧАЛО) == тело.count(КОНЕЦ) == 1, 'неоднозначная рабочая область отчёта')
    область = тело.split(НАЧАЛО, 1)[1].split(КОНЕЦ, 1)[0]
    совпадение = re.fullmatch(r'\n```json\n(.*?)\n```\n\n(.*)', область, re.S)
    требовать(совпадение is not None and '<!-- ШАБЛОН:' not in область,
        'рабочая область P.2 не заполнена либо имеет неизвестный формат')
    метаданные = разобрать(совпадение[1])
    контракт.поля(метаданные, {'схема', 'этап', 'исходный_коммит', 'ожидания',
        'выполнение', 'запуски', 'содержимое_sha256', 'разрешение_установки'})
    содержание = совпадение[2]
    требовать(метаданные['схема'] == 'fum.рабочая-область-отчёта-состояния.1'
        and метаданные['этап'] == план['идентификатор']
        and метаданные['исходный_коммит'] == план['исходный_коммит']
        and метаданные['ожидания'] == план['доверие']['источник']
        and метаданные['выполнение'] == 'выполнено'
        and метаданные['разрешение_установки'] is False
        and метаданные['содержимое_sha256'] == контракт.хэш(содержание.encode())
        and type(метаданные['запуски']) is list
        and метаданные['запуски'] and len(set(метаданные['запуски'])) == len(метаданные['запуски']),
        'рабочий отчёт не соответствует своему P.2/H/R или выполнению')
    return метаданные, содержание


def проверить_отчёт(параметры, создатель, *, сообщение=None):
    """Собственный строгий формат P.2; generic validate_session не применяется."""
    корень, план, привязка, каталог = _контекст(параметры, параметры['выбранное_поручение'])
    установленная = _прочитать_квитанцию(корень, план, привязка, каталог)
    требовать('привязка_повтора' not in параметры or параметры['привязка_повтора'] == установленная,
        'подменена подготовленная повторная пара')
    метаданные, содержание = рабочая_область(параметры, план)
    связность = создатель.связность
    запрос = корень / параметры['запрос']
    отчёт = запрос.with_name('отчёт.md')
    структура = связность.markdown_structural_text(содержание)
    ошибки = []
    for заголовок in ('Результат', 'Проверки и профиль', 'Оставшиеся границы',
            'Использованные инструменты', 'Повлиял на файлы', 'Профиль времени выполнения'):
        требовать(структура.splitlines().count('## ' + заголовок) == 1
            and (связность.section_body(содержание, заголовок) or '').strip(),
            'нет единственного содержательного раздела рабочего отчёта: ' + заголовок)
    ошибки.extend(связность.validate_used_tools_section(содержание, запрос))
    ошибки.extend(связность.validate_journal_time_profile(содержание))
    состав, ошибки_состава = связность.affected_files_from_request(содержание, отчёт, корень)
    ошибки.extend(ошибки_состава)
    требовать(not состав.existing_directories and not состав.deleted_subtrees
        and not состав.deleted_direct_files_directories
        and set(состав) == {корень / имя for имя in параметры['разрешённые_цели']},
        'рабочий отчёт требует точные прямые ссылки на весь T без каталогов')
    for имя in параметры['разрешённые_цели']:
        _прочитать(_точный_путь(корень, имя), приватный=(имя == параметры['история_модели']))
    _, строки, пути = создатель.охват.прочитать_статус(корень)
    требовать(set(пути) <= set(параметры['разрешённые_цели']), 'фактический состав выходит за T повторного этапа')
    ошибки.extend(связность.validate_git_status(корень, состав, строки))
    ошибки.extend(связность.validate_markdown_links({запрос, отчёт}, корень))
    ошибки.extend(связность.validate_answered_question_files(корень, {запрос, отчёт}))
    ошибки.extend(связность.validate_provenance_section_position({запрос, отчёт}, корень))
    ошибки.extend(связность.validate_mermaid_markdown_list_labels({запрос, отчёт}, корень))
    проверить_корневую_метку(параметры, связность, сообщение)
    # P.2 имеет самостоятельный RAW-раздел. Настоящий reporter проверяет
    # его сумму, строки, открытые маркеры, текущие отпечатки и терминальность.
    ошибки.extend(создатель.отчёты.проверить_журнал_сессии(корень, запрос,
        контрольная_точка=True, идентификатор_активного_запуска=None))
    _, _, _, каталог_проверок, сессия = создатель.отчёты.разрешить_сессию(корень, запрос)
    записи = создатель.отчёты.прочитать_историю_проверок(каталог_проверок, сессия)
    требовать(метаданные['запуски'] == [запись['идентификатор'] for _, запись, _ in записи],
        'рабочий отчёт потерял порядок или экземпляр прямого запуска')
    требовать(all(з['схема'] == 'fum.test-run.v4' and з['состояние'] == 'завершён'
        for _, з, _ in записи), 'P.2 требует терминальную историю v4')
    from связность_независимого_журнала import модуль_свежести, чтение_без_обновления_индекса
    with чтение_без_обновления_индекса():
        ошибки.extend(модуль_свежести().update_repository(корень, check=True).errors)
    требовать(not ошибки, '; '.join(ошибки))
    return {'план': план, 'привязка': привязка, 'метаданные': метаданные}


def ранний_охват(параметры, создатель):
    проверить_отчёт(параметры, создатель)
    корень = Path(параметры['корень'])
    def снимок():
        статус, _, пути = создатель.охват.прочитать_статус(корень)
        входы = {}
        for имя in параметры['разрешённые_цели']:
            данные, с = _прочитать(_точный_путь(корень, имя), приватный=(имя == параметры['история_модели']))
            входы[имя] = {'sha256': контракт.хэш(данные), 'режим': stat.S_IMODE(с.st_mode),
                **_метка(с), 'байты': с.st_size, 'изменение_нс': с.st_mtime_ns, 'метаданные_нс': с.st_ctime_ns}
        модули = состав_кода()
        требовать(контракт.хэш(Path(__file__).read_bytes()) == КОД_ПРИ_ЗАГРУЗКЕ,
            'загруженный код повторного Журнала изменился')
        return {'схема': 'fum.ранний-охват-повторного-эффекта.1',
            'корень_sha256': контракт.хэш(str(корень).encode()),
            'ветка': полномочия.гит.гит(корень, 'symbolic-ref', 'HEAD'),
            'коммит': полномочия.гит.гит(корень, 'rev-parse', 'HEAD'),
            'статус_sha256': контракт.хэш(статус), 'индекс_sha256': создатель.индекс(корень),
            'цели': параметры['разрешённые_цели'], 'пути': пути, 'входы': входы, 'модули': модули}
    первый = снимок()
    требовать(снимок() == первый, 'вход повторного охвата изменился при чтении')
    return первый



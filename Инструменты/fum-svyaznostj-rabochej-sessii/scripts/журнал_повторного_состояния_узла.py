def сверить_привязку(параметры, привязка, поручение=None):
    """Закрытая структура сохранённого контекста; без чтения рабочего состояния."""
    поручение = параметры.get('привязка_поручения') if поручение is None else поручение
    контракт.поля(поручение, {'выбранное_поручение', 'нативное_начало', 'нативное_поручение', 'полномочия_узла'})
    контракт.поля(поручение['полномочия_узла'], {'источник', 'значение'})
    а = поручение['полномочия_узла']['значение']
    контракт.поля(а, полномочия.ПОЛЯ)
    контракт.поля(привязка, {'схема', 'цепь', 'квитанция', 'документ'})
    цепь = привязка['цепь']
    контракт.поля(цепь, {'схема', 'корень', 'ветка', 'владелец', 'исходный_коммит',
        'контрольная_ветка', 'акт', 'полномочия', 'план', 'этап', 'цели'})
    требовать(параметры['схема'] == 'fum.создание-коммита.11'
        and привязка['схема'] == 'fum.привязка-повторного-журнала.1'
        and цепь['схема'] == СХЕМА and а['схема'] == полномочия.СХЕМА
        and поручение['выбранное_поручение'] == цепь['акт'] == параметры['выбранное_поручение']
        and цепь['полномочия'] == поручение['полномочия_узла']['источник']
        and цепь['план'] == а['план_журнала']
        and цепь['контрольная_ветка'] == а['контрольная_ветка']
        and цепь['корень'] == параметры['корень']
        and цепь['ветка'] == а['ветка'] == параметры['ветка']
        and цепь['владелец'] == а['владелец'] == параметры['исполнитель']
        and цепь['исходный_коммит'] == а['исходный_коммит'] == параметры['исходный_коммит']
        and цепь['цели'] == а['цели'] == параметры['разрешённые_цели']
        and type(цепь['этап']) is str and цепь['этап'], 'чужая сохранённая привязка повторного этапа')
    документ = привязка['документ']
    контракт.поля(документ, {'схема', 'привязка', 'папка', 'файлы'})
    требовать(документ['схема'] == 'fum.квитанция-повторного-журнала.1'
        and документ['привязка'] == цепь and type(документ['файлы']) is list
        and len(документ['файлы']) == 2, 'повреждена сохранённая квитанция пары')
    def метка(значение):
        контракт.поля(значение, {'устройство', 'номер_файла'})
        требовать(all(type(в) is int and в >= 0 for в in значение.values()), 'повреждена метка сохранённой пары')
    метка(документ['папка'])
    for файл, имя in zip(документ['файлы'], (параметры['запрос'],
            str(Path(параметры['запрос']).with_name('отчёт.md'))), strict=True):
        контракт.поля(файл, {'путь', 'sha256', 'режим', 'устройство', 'номер_файла'})
        требовать(файл['путь'] == имя and файл['режим'] == 0o644
            and type(файл['sha256']) is str and re.fullmatch('[0-9a-f]{64}', файл['sha256']),
            'сохранённая пара содержит другой файл')
        метка({к: файл[к] for к in ('устройство', 'номер_файла')})
    контракт.поля(привязка['квитанция'], {'путь', 'sha256'})
    контракт.поля(параметры['повторный_журнал'], {'каталог'})
    каталог = параметры['повторный_журнал']['каталог']
    требовать(type(каталог) is str and Path(каталог).is_absolute() and Path(каталог).as_posix() == каталог
        and '..' not in Path(каталог).parts and привязка['квитанция'] == {
            'путь': str(Path(каталог) / 'квитанция.json'), 'sha256': контракт.хэш(байты(документ))},
        'сохранённый адрес или хэш квитанции изменён')


def сверить_доказательство(параметры, доказательство):
    сверить_привязку(параметры, параметры['привязка_повтора'])
    контракт.поля(доказательство, {'схема', 'контекст_sha256', 'отчёт', 'охват'})
    требовать(доказательство['схема'] == 'fum.доказательство-пары-повторного-эффекта.1'
        and доказательство['контекст_sha256'] == контракт.хэш(байты(параметры['привязка_повтора']))
        and доказательство['отчёт'] == str(Path(параметры['запрос']).with_name('отчёт.md'))
        and type(доказательство['охват']) is dict
        and доказательство['охват'].get('схема') == 'fum.ранний-охват-повторного-эффекта.1',
        'подменено доказательство повторной пары')
    охват = доказательство['охват']
    контракт.поля(охват, {'схема', 'корень_sha256', 'ветка', 'коммит', 'статус_sha256',
        'индекс_sha256', 'цели', 'пути', 'входы', 'модули'})
    def сумма(значение):
        return type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение) is not None
    требовать(охват['корень_sha256'] == контракт.хэш(параметры['корень'].encode())
        and охват['ветка'] == параметры['ветка'] and охват['коммит'] == параметры['исходный_коммит']
        and охват['цели'] == параметры['разрешённые_цели']
        and type(охват['пути']) is list and all(type(п) is str for п in охват['пути'])
        and len(set(охват['пути'])) == len(охват['пути'])
        and set(охват['пути']) <= set(охват['цели'])
        and сумма(охват['статус_sha256']) and сумма(охват['индекс_sha256'])
        and type(охват['входы']) is dict and set(охват['входы']) == set(охват['цели'])
        and type(охват['модули']) is dict and охват['модули'], 'повреждён закрытый охват пары')
    for имя, запись in охват['входы'].items():
        контракт.поля(запись, {'sha256', 'режим', 'устройство', 'номер_файла', 'байты', 'изменение_нс', 'метаданные_нс'})
        требовать(сумма(запись['sha256']) and запись['режим'] ==
            (0o600 if имя == параметры['история_модели'] else 0o644)
            and all(type(запись[к]) is int and запись[к] >= 0 for к in запись if к != 'sha256'),
            'неверное историческое наблюдение файла пары')
    требовать(all(type(имя) is str and Path(имя).as_posix() == имя
        and not Path(имя).is_absolute() and not {'..', '.', '.git'}.intersection(Path(имя).parts)
        and type(значение) is dict and set(значение) == {'sha256', 'режим'}
        and сумма(значение['sha256']) and type(значение['режим']) is int
        and значение['режим'] in {0o644, 0o755}
        for имя, значение in охват['модули'].items()), 'неверный состав кода пары')


def установить(параметры, *, доверенное_поручение):
    """Новый эффект либо строго читающий повтор уже завершённой установки."""
    корень, план, привязка, каталог = _контекст(параметры, доверенное_поручение)
    намерение = каталог / 'намерение.json'
    квитанция = каталог / 'квитанция.json'
    эпизод = _путь_эпизода(корень, план)
    if os.path.lexists(эпизод) or os.path.lexists(намерение) or os.path.lexists(квитанция):
        итог = _прочитать_квитанцию(корень, план, привязка, каталог)
        return {'квитанция': итог['квитанция'],
            'без_повторных_эффектов': True}
    папка = _точный_путь(корень, str(Path(план['файлы'][0]['путь']).parent))
    требовать(not os.path.lexists(папка), 'частичная или чужая папка пары уже существует')
    требовать(папка.parent.is_dir(), 'родитель нового Журнала отсутствует')
    требовать(not полномочия.гит.выполнить(корень, 'diff', '--cached', '--name-only', '-z').stdout,
        'индекс перед установкой пары не пуст')
    for исходный in план['файлы']:
        адрес = _точный_путь(корень, исходный['путь'])
        требовать(not os.path.lexists(адрес), 'остаток файла пары до установки')
        требовать(not полномочия.гит.выполнить(корень, 'ls-files', '-z', '--', исходный['путь']).stdout,
            'файл пары уже существует в индексе')
        требовать(полномочия.гит.выполнить(корень, 'check-ignore', '-q', '--no-index', '--',
            исходный['путь'], допустимые=(0, 1)).returncode == 1, 'пара скрыта ignore-правилом')
    # Первым сохраняется намерение. Любой последующий отказ сохраняет остаток
    # для разбора; установка не дописывает чужие половины и не откатывает их.
    _поздний_допуск(параметры, привязка)
    if not os.path.lexists(эпизод.parent):
        админ = _открыть_каталог(эпизод.parent.parent)
        try:
            os.mkdir(эпизод.parent.name, mode=0o700, dir_fd=админ)
            os.fsync(админ)
        finally:
            os.close(админ)
    состояние = эпизод.parent.lstat()
    требовать(stat.S_ISDIR(состояние.st_mode) and stat.S_IMODE(состояние.st_mode) == 0o700
        and состояние.st_uid == os.getuid(), 'небезопасный каталог устойчивого эпизода')
    _поздний_допуск(параметры, привязка)
    _создать(эпизод, _байты_эпизода(привязка, каталог), 0o600)
    _поздний_допуск(параметры, привязка)
    _создать(намерение, байты(привязка), 0o600)
    _поздний_допуск(параметры, привязка)
    _точный_путь(корень, str(папка.relative_to(корень)))
    родитель = _открыть_каталог(папка.parent)
    try:
        os.mkdir(папка.name, mode=0o755, dir_fd=родитель)
        os.fsync(родитель)
    finally:
        os.close(родитель)
    закреплённый = _открыть_каталог(папка)
    try:
        os.fchmod(закреплённый, 0o755)
        метка_папки = _метка(os.fstat(закреплённый))
    finally:
        os.close(закреплённый)
    _синхронизировать(папка.parent)
    записи = []
    for исходный in план['файлы']:
        адрес = папка / Path(исходный['путь']).name
        _поздний_допуск(параметры, привязка)
        _точный_путь(корень, исходный['путь'])
        _создать(адрес, исходный['текст'].encode(), исходный['режим'], родитель=метка_папки)
        данные, метка = _прочитать(адрес)
        требовать(контракт.хэш(данные) == исходный['sha256'], 'записаны другие байты пары')
        записи.append({к: исходный[к] for к in ('путь', 'sha256', 'режим')} | _метка(метка))
    документ = {'схема': 'fum.квитанция-повторного-журнала.1', 'привязка': привязка,
        'папка': метка_папки, 'файлы': записи}
    _сверить_пару(корень, план, документ)
    сырые = байты(документ)
    _поздний_допуск(параметры, привязка)
    _создать(квитанция, сырые, 0o600)
    return {'квитанция': {'путь': str(квитанция), 'sha256': контракт.хэш(сырые)},
        'без_повторных_эффектов': False}

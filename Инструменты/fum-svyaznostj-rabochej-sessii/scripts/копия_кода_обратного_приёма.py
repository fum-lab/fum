"""Конечная приватная копия Git-байтов L без создания ветки или worktree.

Список выбирает принимающий контур; копия сама не предоставляет полномочий.
Частично созданный каталог сохраняется и не используется повторно.
"""
import hashlib
import os
from pathlib import Path
import stat

from конечный_состав_независимого_контура import (
    байты, гит, прочитать_набор, разобрать, точный_путь, требовать)


def _каталог(значение):
    путь = Path(значение)
    требовать(путь.is_absolute() and путь.resolve() == путь, "Нужен физический каталог копии")
    for часть in (путь, *путь.parents):
        требовать(not часть.is_symlink(), "Ссылка в пути копии")
        требовать(not os.path.lexists(часть / ".git"), "Копия должна находиться вне Git")
        требовать(not ((часть / "HEAD").is_file() and (часть / "objects").is_dir()),
                  "Копия должна находиться вне bare Git")
    родитель = путь if путь.exists() else путь.parent
    состояние = родитель.stat()
    требовать(stat.S_ISDIR(состояние.st_mode) and состояние.st_uid == os.getuid()
              and stat.S_IMODE(состояние.st_mode) == 0o700, "Нужен собственный приватный каталог")
    return путь


def _сохранить(путь, данные, режим):
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, режим)
    with os.fdopen(дескриптор, "wb") as поток:
        поток.write(данные)
        поток.flush()
        os.fchmod(поток.fileno(), режим)
        os.fsync(поток.fileno())


def _свойства(состояние):
    return (состояние.st_dev, состояние.st_ino, состояние.st_mode, состояние.st_uid,
            состояние.st_nlink, состояние.st_size, состояние.st_mtime_ns,
            состояние.st_ctime_ns)


def проверить(каталог, ожидаемый_sha256):
    """Проверить точную копию по независимо сохранённому SHA, только чтение."""
    каталог = _каталог(каталог)
    манифест = каталог / "манифест.json"
    требовать(манифест.is_file() and not манифест.is_symlink(), "Нет манифеста копии")
    сырые = манифест.read_bytes()
    требовать(hashlib.sha256(сырые).hexdigest() == ожидаемый_sha256, "Изменился SHA копии")
    данные = разобрать(сырые)
    требовать(type(данные) is dict and set(данные) == {"схема", "коммит", "файлы"}
              and данные["схема"] == "fum.копия-кода-обратного-приёма.1", "Неверная копия кода")
    записи = данные["файлы"]
    требовать(type(записи) is list and записи, "Нет конечного состава копии")
    имена = [точный_путь(запись["путь"]) for запись in записи]
    требовать(len(имена) == len(set(имена)) and "манифест.json" not in имена, "Повтор пути копии")
    файлы = {"манифест.json", *имена}
    каталоги = {предок.as_posix() for имя in имена for предок in Path(имя).parents
                if предок.as_posix() != "."}
    фактические_файлы, фактические_каталоги = set(), set()
    for корень, вложенные, обычные in os.walk(каталог, followlinks=False):
        for имя in [*вложенные, *обычные]:
            путь = Path(корень) / имя
            состояние = путь.lstat()
            требовать(not stat.S_ISLNK(состояние.st_mode) and состояние.st_uid == os.getuid(),
                      "Ссылка или чужой владелец копии")
            относительный = путь.relative_to(каталог).as_posix()
            if stat.S_ISDIR(состояние.st_mode):
                требовать(stat.S_IMODE(состояние.st_mode) == 0o700, "Изменён режим каталога копии")
                фактические_каталоги.add(относительный)
            else:
                требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1,
                          "Необычный файл копии")
                фактические_файлы.add(относительный)
    требовать(файлы == фактические_файлы and каталоги == фактические_каталоги,
              "Изменён конечный состав копии")
    требовать(stat.S_IMODE(манифест.stat().st_mode) == 0o400, "Изменён режим манифеста")
    for запись in записи:
        путь = каталог / запись["путь"]
        требовать(set(запись) == {"путь", "режим", "объект", "sha256"}
                  and запись["режим"] in ("100644", "100755"), "Неизвестная запись копии")
        режим = 0o500 if запись["режим"] == "100755" else 0o400
        до = путь.stat()
        исходник = путь.read_bytes()
        после = путь.stat()
        требовать(_свойства(до) == _свойства(после) and stat.S_IMODE(после.st_mode) == режим
                  and hashlib.sha256(исходник).hexdigest() == запись["sha256"]
                  and hashlib.sha1(b"blob " + str(len(исходник)).encode() + b"\0" + исходник).hexdigest()
                  == запись["объект"], "Изменились байты или режим копии")
    требовать(манифест.read_bytes() == сырые, "Манифест изменился при чтении")
    return данные


def материализовать(корень, коммит, каталог, пути):
    """Сохранить один явно выбранный состав до изменения принимающего checkout."""
    каталог = _каталог(каталог)
    требовать(not os.path.lexists(каталог), "Каталог копии уже существует")
    пути = list(пути)
    требовать("манифест.json" not in пути, "Путь занят манифестом копии")
    требовать(гит(корень, "rev-parse", "HEAD").decode().strip() == коммит,
              "Принимающий HEAD изменился")
    записи = прочитать_набор(корень, коммит, пути)
    данные = {"схема": "fum.копия-кода-обратного-приёма.1", "коммит": коммит,
              "файлы": [записи[путь][0] for путь in sorted(записи)]}
    каталог.mkdir(mode=0o700)
    for имя, (запись, исходник) in записи.items():
        путь = каталог / имя
        for предок in reversed(путь.parent.parents):
            if предок.is_relative_to(каталог) and not предок.exists():
                предок.mkdir(mode=0o700)
        if not путь.parent.exists():
            путь.parent.mkdir(mode=0o700)
        _сохранить(путь, исходник, 0o500 if запись["режим"] == "100755" else 0o400)
    требовать(прочитать_набор(корень, коммит, пути) == записи
              and гит(корень, "rev-parse", "HEAD").decode().strip() == коммит,
              "Принимающий код изменился во время копирования")
    сырые = байты(данные)
    _сохранить(каталог / "манифест.json", сырые, 0o400)
    for корень_каталога, _, _ in os.walk(каталог, topdown=False):
        дескриптор = os.open(корень_каталога, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            os.fsync(дескриптор)
        finally:
            os.close(дескриптор)
    отпечаток = hashlib.sha256(сырые).hexdigest()
    проверить(каталог, отпечаток)
    return {"sha256": отпечаток, "коммит": коммит, "файлов": len(записи)}

"""Точная граница ограниченного выбора без изменения происхождения остатка."""
import copy
import re


def проверить_границу(граница, требовать):
    требовать(type(граница) is dict and set(граница) == {
        'граница', 'sha256', 'неоднозначные_экземпляры'}, 'нужна точная граница выбранного снимка')
    требовать(type(граница['граница']) is int and граница['граница'] > 0
        and type(граница['sha256']) is str and re.fullmatch(r'[0-9a-f]{64}', граница['sha256']),
        'неверные байтовая граница или SHA256 снимка')
    остаток = граница['неоднозначные_экземпляры']
    требовать(type(остаток) is list and all(type(э) is str and re.fullmatch(r'[0-9a-f]{64}', э) for э in остаток)
        and len(set(остаток)) == len(остаток), 'неверный состав неоднозначного остатка')


def проверить_снимок(снимок, граница, требовать):
    проверить_границу(граница, требовать)
    требовать(снимок['неполный_хвост'] == 0 and снимок['дописано_после_снимка'] == 0
        and снимок['граница'] == снимок['размер_снимка'] == граница['граница']
        and снимок['sha256'] == граница['sha256'], 'изменился завершённый первичный снимок выбора')
    остаток = [э['экземпляр'] for э in снимок['сообщения'] if э['происхождение'] != 'человек']
    требовать(остаток == граница['неоднозначные_экземпляры'], 'изменился полный неоднозначный остаток')


def привязка_источников(источники, требовать):
    требовать(type(источники) is list and bool(источники), 'нужны источники ограниченного выбора')
    результат = []
    for источник in источники:
        проверить_границу(источник.get('граница_снимка'), требовать)
        результат.append({к: copy.deepcopy(источник[к]) for к in ('путь', 'задача', 'граница_снимка')})
    return {'источники': результат}

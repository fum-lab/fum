"""Отдельная линейная история решений; штатные обработка и guard только читаются."""
import copy
import hashlib
import os
import time
import uuid
from pathlib import Path

import обработка_сообщений as штатная

читатель = штатная.читатель
гит = штатная.гит
СХЕМА = 'fum.локальная-обработка-сообщений.1'
ПОЛЯ = {'номер', 'предыдущий', 'основа', 'событие', 'уточняет', 'запись', 'неизвестные',
        'классификатор_sha256', 'читатель_sha256', 'обычная_история_sha256', 'завершение_задачи_доказано'}


class ОшибкаЛокальногоРешения(штатная.ОшибкаОбработки):
    """Не удалось подтвердить отдельное решение."""


class НеизвестныйИсход(ОшибкаЛокальногоРешения):
    """Установка могла произойти; повторять только точный прежний вход."""


def требовать(условие, причина):
    if not условие:
        raise ОшибкаЛокальногоРешения(причина)


def путь_истории(задача):
    требовать(type(задача) is str and str(uuid.UUID(задача)) == задача, 'нужен канонический UUID ROOT')
    return str(Path(штатная.путь_истории(задача)).with_name('локальные-решения-сообщений.jsonl'))


def версии_читателей():
    версии = {'читатель_sha256': штатная.хэш(штатная.прочитать_файл(Path(читатель.__file__))),
              'классификатор_sha256': штатная.хэш(штатная.прочитать_файл(читатель._ПУТЬ_КЛАССИФИКАТОРА))}
    требовать(версии == {'читатель_sha256': читатель.КОД_ПРИ_ЗАГРУЗКЕ,
              'классификатор_sha256': читатель._КЛАССИФИКАТОР.КОД_ПРИ_ЗАГРУЗКЕ},
              'сырые версии не равны реально загруженным читателю и классификатору')
    return версии


def неизвестные(снимок, граница):
    return [э['экземпляр'] for э in снимок['сообщения']
            if э['позиция']['конец'] <= граница and э['происхождение'] != 'человек']


def разобрать_историю(байты, задача, источник):
    if not байты:
        return []
    требовать(байты.endswith(b'\n'), 'неполная локальная история')
    строки = байты.splitlines(keepends=True)
    заголовок = читатель._разобрать(строки[0])
    штатная.объект(заголовок, {'схема', 'задача', 'источник'})
    требовать(заголовок == {'схема': СХЕМА, 'задача': задача, 'источник': источник}
              and строки[0] == читатель._байты(заголовок) and len(строки) > 1,
              'неверный заголовок локальной истории')
    префикс = hashlib.sha256(строки[0])
    предыдущий = штатная.хэш(строки[0])
    последние = {}
    граница = 0
    результат = []
    for номер, строка in enumerate(строки[1:], 1):
        событие = читатель._разобрать(строка)
        штатная.объект(событие, ПОЛЯ)
        штатная.проверить_предложение(событие['запись'])
        for имя in ('предыдущий', 'основа', 'событие', 'читатель_sha256',
                    'классификатор_sha256', 'обычная_история_sha256'):
            штатная.отпечаток(событие[имя])
        требовать(читатель._байты(событие) == строка and type(событие['номер']) is int
                  and событие['номер'] == номер and событие['предыдущий'] == предыдущий,
                  'разрыв или неканонические байты локальной цепочки')
        требовать(событие['основа'] == (штатная.хэш(b'') if номер == 1 else префикс.hexdigest()),
                  'основа не равна сырым прежним локальным байтам')
        экземпляр = событие['запись']['экземпляр']
        требовать(событие['уточняет'] == последние.get(экземпляр), 'пересмотр не связан с последним решением')
        требовать(событие['завершение_задачи_доказано'] is False, 'локальный слой не разрешает завершение ROOT')
        список = событие['неизвестные']
        требовать(type(список) is list and len(список) == len(set(список)), 'неверный перечень неизвестных')
        for имя in список:
            штатная.отпечаток(имя)
        тело = {к: з for к, з in событие.items() if к != 'событие'}
        требовать(событие['событие'] == штатная.хэш(читатель._байты(тело)), 'подменён конверт локального события')
        новая = событие['запись']['контекст']['граница']
        требовать(новая >= граница, 'граница локального рассмотрения откатилась')
        граница = новая
        последние[экземпляр] = событие['событие']
        предыдущий = штатная.хэш(строка)
        префикс.update(строка)
        результат.append(событие)
    return результат


def сверить_публикацию(корень, запись, исходное, допустимые_части_sha256):
    """SHA полного массива частей — отдельный явный допуск вызывающего корня."""
    штатная.отпечаток(допустимые_части_sha256)
    требовать(допустимые_части_sha256 == штатная.хэш(читатель._байты(исходное['содержимое'])),
              'нет явного допуска полных частей человеческой команды к публикации')
    # Адресный сканер не доказывает отсутствие секретов или человеческое полномочие.
    # Они входят в смысл предварительного допуска, отдельно от целостности команды.
    import подготовка_дочернего_поручения as подготовка
    файлы = {запись[имя]['путь']: штатная.прочитать_файл(штатная.локальный_путь(корень, запись[имя]['путь']))
             for имя in ('команда', 'ответ', 'основание')}
    подготовка.публикация(корень, файлы)


class Сеанс:
    def __init__(сам, источник, задача, корень, кэш):
        сам.начало = time.perf_counter_ns()
        сам.корень = Path(корень)
        требовать(сам.корень.is_absolute() and сам.корень == сам.корень.resolve(strict=True),
                  'нужен физический абсолютный корень checkout')
        требовать(гит.выполнить_чтение_репозитория(сам.корень, 'rev-parse', '--show-toplevel').decode().strip()
                  == str(сам.корень), 'путь не является корнем checkout')
        сам.путь = штатная.локальный_путь(сам.корень, путь_истории(задача))
        сам.обычная = штатная.локальный_путь(сам.корень, штатная.путь_истории(задача))
        сам.задача = задача
        сам.источник = Path(источник)
        требовать(сам.источник.is_absolute() and сам.источник == сам.источник.resolve(strict=True),
                  'нужен физический путь native без символических ссылок')
        сам.чтение = читатель._сеанс_чтения(сам.источник, задача, корень_репозитория=сам.корень,
                                          кэш=кэш, без_записи=True)
        сам.версии = версии_читателей()
        сам.кэш = кэш
        сам.файлы = {}
        сам.профиль = {'читатели': {}, 'построений_предложения': 0}

    def учесть(сам, имя, начало, *, байтов=0):
        счётчик = сам.профиль['читатели'].setdefault(имя, {'вызовов': 0, 'байтов': 0, 'наносекунды': 0})
        счётчик['вызовов'] += 1
        счётчик['байтов'] += байтов
        счётчик['наносекунды'] += time.perf_counter_ns() - начало

    def файл(сам, имя):
        if имя not in сам.файлы:
            начало = time.perf_counter_ns()
            путь = штатная.локальный_путь(сам.корень, имя)
            сам.файлы[имя] = штатная.прочитать_файл(путь) if os.path.lexists(путь) else None
            сам.учесть('текущие_свидетельства', начало, байтов=len(сам.файлы[имя] or b''))
        return сам.файлы[имя]

    def загрузить(сам):
        начало = time.perf_counter_ns()
        сам.снимок, сам.сырые_обычные, _, сам.граф, профиль = штатная.загрузить(
            сам.источник, сам.задача, сам.корень, сам.кэш, False,
            кэшировать_границы=False, без_записи=True, чтение=сам.чтение)
        сам.учесть('штатный_диалог_и_обычная_история', начало,
                   байтов=профиль['диалог']['прочитано_байтов'] + len(сам.сырые_обычные))
        сам.профиль['штатная_загрузка'] = профиль
        сам.сырые = штатная.прочитать_файл(сам.путь) if os.path.lexists(сам.путь) else b''
        сам.ветка = гит.выполнить_чтение_репозитория(сам.корень, 'symbolic-ref', 'HEAD').decode().strip()
        требовать(сам.ветка.startswith('refs/heads/'), 'нет полного ref checkout')
        начало = time.perf_counter_ns()
        сам.деревья = гит._СеансДеревьев(сам.корень, сам.граф['деревья'])
        состояния = сам.деревья.состояния_пути(путь_истории(сам.задача))
        объекты = {з[1] for з in состояния.values() if з is not None}
        сам.объекты = гит.прочитать_объекты(сам.корень, объекты, 'blob') if объекты else {}
        версии = {к: b'' if з is None else сам.объекты[з[1]] for к, з in состояния.items()}
        разобранные = {}
        сам.содержащие = {}
        for коммит, байты in версии.items():
            if байты not in разобранные:
                разобранные[байты] = разобрать_историю(байты, сам.задача, сам.снимок['источник'])
            for событие in разобранные[байты]:
                сам.содержащие.setdefault(событие['событие'], []).append(коммит)
            for родитель in сам.граф['родители'][коммит]:
                требовать(байты.startswith(версии[родитель]), 'локальная история переписана или удалена на Git-ребре')
        требовать(all(сам.сырые.startswith(версии[к]) for к in сам.граф['корни']),
                  'checkout не сохраняет все родительские локальные префиксы')
        сам.события = разобрать_историю(сам.сырые, сам.задача, сам.снимок['источник'])
        сам.учесть('локальная_история_Git', начало,
                   байтов=len(сам.сырые) + sum(map(len, сам.объекты.values())) + сам.деревья.размер_кэша)
        начало = time.perf_counter_ns()
        контексты = [э['запись']['контекст'] for э in сам.события]
        границы = штатная.сверить_границы(сам.источник, контексты, без_записи=True)
        сам.учесть('сырые_префиксы_native', начало, байтов=границы['прочитано_байтов'])
        сам.исходные = {}
        for событие in сам.события:
            запись = событие['запись']
            сам.исходные[событие['событие']] = штатная.сверить_экземпляры(запись, сам.снимок)
            требовать(событие['неизвестные'] == неизвестные(сам.снимок, запись['контекст']['граница']),
                      'пропуск или перестановка неизвестных экземпляров')
        return сам

    def оценки(сам):
        последние = {}
        состояния = {}
        версии = dict(сам.объекты)
        результат = []
        сам.оценки_событий = []
        for событие in сам.события:
            запись = событие['запись']
            причины = []
            try:
                штатная.сверить_свидетельства(запись, сам.исходные[событие['событие']], сам.файл)
            except (OSError, ValueError, UnicodeError):
                причины.append('текущее свидетельство недоступно или изменено')
            for имя in ('команда', 'ответ', 'основание'):
                путь = запись[имя]['путь']
                if путь not in состояния:
                    состояния[путь] = сам.деревья.состояния_пути(путь)
            выбранные = сам.содержащие.get(событие['событие'], [])
            недостающие = {состояния[запись[имя]['путь']][к][1]
                for к in выбранные for имя in ('команда', 'ответ', 'основание')
                if состояния[запись[имя]['путь']][к] is not None} - версии.keys()
            if недостающие:
                начало = time.perf_counter_ns()
                новые = гит.прочитать_объекты(сам.корень, недостающие, 'blob')
                версии.update(новые)
                сам.учесть('исторические_свидетельства_Git', начало, байтов=sum(map(len, новые.values())))
            for коммит in выбранные:
                def читать(путь):
                    состояние = состояния[путь][коммит]
                    return None if состояние is None else версии[состояние[1]]
                try:
                    штатная.сверить_свидетельства(запись, сам.исходные[событие['событие']], читать)
                except (ValueError, UnicodeError):
                    причины.append('исторический разрыв свидетельства')
                    break
            if any(э['позиция']['конец'] > запись['контекст']['граница'] for э in сам.снимок['сообщения']):
                причины.append('новый человеческий или неизвестный ввод')
            if сам.снимок['неполный_хвост'] or сам.снимок['дописано_после_снимка']:
                причины.append('непроверенный хвост источника')
            if any(событие[имя] != сам.версии[имя] for имя in сам.версии):
                причины.append('изменилась версия читателя или классификатора')
            if событие['обычная_история_sha256'] != штатная.хэш(сам.сырые_обычные):
                причины.append('изменилась обычная история')
            последние[запись['экземпляр']] = {'экземпляр': запись['экземпляр'], 'событие': событие['событие'],
                'запись': copy.deepcopy(запись), 'причины': причины,
                'переиспользуемо': not причины and запись['актуальность'] != 'неясно'}
            сам.оценки_событий.append(последние[запись['экземпляр']])
        результат.extend(последние.values())
        сам.деревья.проверить_доступность()
        return результат

    def заключить(сам):
        начало = time.perf_counter_ns()
        прочитано_байтов = 0
        свежий = сам.чтение()
        требовать(штатная.контекст_снимка(свежий) == штатная.контекст_снимка(сам.снимок)
                  and свежий['неполный_хвост'] == сам.снимок['неполный_хвост']
                  and свежий['дописано_после_снимка'] == 0, 'native изменился перед заключением')
        for путь, прежние in ((сам.путь, сам.сырые), (сам.обычная, сам.сырые_обычные)):
            штатная.локальный_путь(сам.корень, путь.relative_to(сам.корень).as_posix())
            текущие = штатная.прочитать_файл(путь) if os.path.lexists(путь) else b''
            прочитано_байтов += len(текущие)
            требовать(текущие == прежние,
                      'история изменилась перед заключением')
        for имя, байты in сам.файлы.items():
            путь = штатная.локальный_путь(сам.корень, имя)
            текущие = штатная.прочитать_файл(путь) if os.path.lexists(путь) else None
            прочитано_байтов += len(текущие or b'')
            требовать(текущие == байты,
                      'свидетельство изменилось перед заключением')
        требовать(гит.выполнить_чтение_репозитория(сам.корень, 'rev-parse', 'HEAD').decode().strip() == сам.граф['вершина']
                  and гит.выполнить_чтение_репозитория(сам.корень, 'symbolic-ref', 'HEAD').decode().strip() == сам.ветка
                  and штатная._слияние_гита(сам.корень) == сам.граф['слияние'], 'HEAD/ref/родители изменились')
        требовать(версии_читателей() == сам.версии, 'код читателя изменился')
        сам.учесть('свежая_сверка', начало, байтов=свежий['профиль']['прочитано_байтов'] + прочитано_байтов)
        сам.профиль['длительность_наносекунды'] = time.perf_counter_ns() - сам.начало


def защищённо(действие, наблюдение):
    try:
        return действие()
    except (OSError, ValueError, TypeError, KeyError, UnicodeError, гит.ОшибкаОтчёта) as ошибка:
        итог = ошибка if isinstance(ошибка, ОшибкаЛокальногоРешения) else ОшибкаЛокальногоРешения(
            'локальная история, источник или свидетельства не подтверждены')
        if наблюдение:
            сеанс = наблюдение[-1]
            итог.профиль = {**сеанс.профиль, 'длительность_наносекунды': time.perf_counter_ns() - сеанс.начало}
        if итог is ошибка: raise
        raise итог from ошибка


def прочитать_локальные_решения(источник, задача, *, корень_репозитория, кэш=None):
    наблюдение = []
    def прочитать():
        сеанс = Сеанс(источник, задача, корень_репозитория, кэш)
        наблюдение.append(сеанс)
        сеанс.загрузить()
        решения = сеанс.оценки()
        сеанс.заключить()
        return {'схема': СХЕМА, 'задача': задача, 'источник': сеанс.снимок['источник'],
            'контекст': штатная.контекст_снимка(сеанс.снимок),
            'неизвестные': неизвестные(сеанс.снимок, сеанс.снимок['граница']),
            'неполный_хвост': сеанс.снимок['неполный_хвост'],
            'локальная_история_sha256': штатная.хэш(сеанс.сырые),
            'обычная_история_sha256': штатная.хэш(сеанс.сырые_обычные), **сеанс.версии,
            'решения': решения, 'оценки_событий': сеанс.оценки_событий,
            'завершение_задачи_доказано': False, 'профиль': сеанс.профиль}
    return защищённо(прочитать, наблюдение)


def сохранить_локальное_решение(источник, задача, *, корень_репозитория, запись,
        ожидаемая_локальная_история, ожидаемая_обычная_история, ожидаемый_читатель,
        ожидаемый_классификатор, допустимые_части_sha256, кэш=None):
    наблюдение = []
    def сохранить():
        штатная.проверить_предложение(запись)
        for отпечаток in (ожидаемая_локальная_история, ожидаемая_обычная_история,
                          ожидаемый_читатель, ожидаемый_классификатор, допустимые_части_sha256):
            штатная.отпечаток(отпечаток)
        сеанс = Сеанс(источник, задача, корень_репозитория, кэш)
        наблюдение.append(сеанс)
        # Подтвердить ROOT штатным читателем до создания служебного lock.
        начало = time.perf_counter_ns()
        предварительный = сеанс.чтение()
        сеанс.учесть('предварительный_штатный_native', начало, байтов=предварительный['профиль']['прочитано_байтов'])
        каталог_гита = Path(os.fsdecode(гит.выполнить_чтение_репозитория(сеанс.корень,
                        'rev-parse', '--absolute-git-dir').rstrip(b'\n')))
        # Тот же физический checkout/ROOT-замок, что у штатной обработки .1/.2.
        with читатель._замок(каталог_гита / ('fum-обработка-' + задача)):
            сеанс.загрузить()
            требовать(not сеанс.граф['слияние'], 'локальная запись во время слияния запрещена')
            for событие in сеанс.события:
                if (событие['основа'] == ожидаемая_локальная_история and событие['запись'] == запись
                        and событие['обычная_история_sha256'] == ожидаемая_обычная_история
                        and событие['читатель_sha256'] == ожидаемый_читатель
                        and событие['классификатор_sha256'] == ожидаемый_классификатор):
                    исходное = сеанс.исходные[событие['событие']]
                    требовать(допустимые_части_sha256 == штатная.хэш(читатель._байты(исходное['содержимое'])),
                              'повтор не имеет прежнего явного допуска публикации')
                    сеанс.заключить()
                    try:
                        with os.fdopen(os.open(сеанс.путь, os.O_RDONLY | os.O_NOFOLLOW), 'rb') as поток:
                            os.fsync(поток.fileno())
                        штатная.синхронизировать_каталог(сеанс.путь.parent)
                    except (OSError, ValueError) as ошибка:
                        raise НеизвестныйИсход('долговечность прежней установки не подтверждена; повторяй только прежний вход') from ошибка
                    сеанс.заключить()
                    строки = сеанс.сырые.splitlines(keepends=True)
                    return {'событие': событие['событие'], 'история_sha256': штатная.хэш(b''.join(строки[:событие['номер'] + 1])),
                        'повтор': True, 'текущая_актуальность_подтверждена': False, 'завершение_задачи_доказано': False}
            требовать(штатная.хэш(сеанс.сырые) == ожидаемая_локальная_история
                      and штатная.хэш(сеанс.сырые_обычные) == ожидаемая_обычная_история, 'CAS одной из историй не совпал')
            требовать(сеанс.версии == {'читатель_sha256': ожидаемый_читатель,
                      'классификатор_sha256': ожидаемый_классификатор}, 'версия читателя или классификатора не совпала')
            требовать(сеанс.снимок['неполный_хвост'] == сеанс.снимок['дописано_после_снимка'] == 0,
                      'незавершённый хвост или непроверенное дописывание')
            требовать(запись['контекст'] == штатная.контекст_снимка(сеанс.снимок), 'новый или неполный рассмотренный контекст')
            штатная.сверить_границы(сеанс.источник, [запись['контекст']], без_записи=True)
            исходное = штатная.сверить_экземпляры(запись, сеанс.снимок)
            штатная.сверить_свидетельства(запись, исходное, сеанс.файл)
            сверить_публикацию(сеанс.корень, запись, исходное, допустимые_части_sha256)
            прежние = сеанс.сырые
            префикс = прежние or читатель._байты({'схема': СХЕМА, 'задача': задача, 'источник': сеанс.снимок['источник']})
            последнее = next((э['событие'] for э in reversed(сеанс.события)
                             if э['запись']['экземпляр'] == запись['экземпляр']), None)
            событие = {'номер': len(сеанс.события) + 1, 'предыдущий': штатная.хэш(префикс.splitlines(keepends=True)[-1]),
                'основа': ожидаемая_локальная_история, 'уточняет': последнее, 'запись': copy.deepcopy(запись),
                'неизвестные': неизвестные(сеанс.снимок, запись['контекст']['граница']), **сеанс.версии,
                'обычная_история_sha256': ожидаемая_обычная_история, 'завершение_задачи_доказано': False}
            событие['событие'] = штатная.хэш(читатель._байты(событие))
            новые = префикс + читатель._байты(событие)
            разобрать_историю(новые, задача, сеанс.снимок['источник'])
            каталог = сеанс.корень
            for часть in сеанс.путь.parent.relative_to(сеанс.корень).parts:
                следующий = каталог / часть
                if not os.path.lexists(следующий): следующий.mkdir()
                требовать(следующий.is_dir() and not следующий.is_symlink(), 'каталог истории подменён')
                штатная.синхронизировать_каталог(каталог)
                каталог = следующий
            сеанс.заключить()
            try:
                читатель._установить(сеанс.путь, новые)
                требовать(штатная.прочитать_файл(сеанс.путь) == новые, 'байты установленного решения не совпали')
            except (OSError, ValueError) as ошибка:
                raise НеизвестныйИсход('установка не подтверждена; сохрани вход и выполни только точный повтор') from ошибка
            return {'событие': событие['событие'], 'история_sha256': штатная.хэш(новые),
                'повтор': False, 'текущая_актуальность_подтверждена': False, 'завершение_задачи_доказано': False}
    return защищённо(сохранить, наблюдение)

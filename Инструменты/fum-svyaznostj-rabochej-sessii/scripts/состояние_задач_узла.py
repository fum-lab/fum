ПРЕДЕЛ = 64 * 1024 * 1024
ИДЕНТИЧНОСТЬ = {"узел", "репозиторий", "координатор", "поколение_полномочий", "владелец"}
ДОПОЛНИТЕЛЬНЫЕ_ТИПЫ = {"sleep", "functionCallOutput", "subAgentActivity"}


def _загрузить_ожидания(доверие, *, корень, профиль=None):
    начало = time.monotonic_ns()
    канон.поля(доверие, {"схема", "ref", "источник"} | ИДЕНТИЧНОСТЬ)
    канон.требовать(доверие["схема"] == "fum.доверие-ожиданиям-узла.1", "неизвестное доверие")
    for поле in ИДЕНТИЧНОСТЬ:
        канон.строка(доверие[поле])
    for поле in ("координатор", "владелец"):
        канон.идентичность(доверие[поле])
    корень = доставка_гит.физический_корень(корень)
    ссылка_ветки = доверие["ref"]
    канон.требовать(type(ссылка_ветки) is str and ссылка_ветки.startswith("refs/heads/"), "нужен полный доверенный ref")
    доставка_гит.выполнить(корень, "check-ref-format", ссылка_ветки)
    канон.источник(доверие["источник"])
    канон.требовать(доставка_гит.гит(корень, "rev-parse", "--verify", ссылка_ветки) == доверие["источник"]["коммит"],
        "изменилось доверенное Git-поколение")
    измерения = {"прочитано_байтов": 0, "чтений_git_источников": 0}
    данные = канон.прочитать_источник(корень, доверие["источник"], измерения)
    ожидания = канон.разобрать(данные)
    канон.поля(ожидания, {"схема", "основание", "предпросмотр"} | ИДЕНТИЧНОСТЬ)
    канон.требовать(ожидания["схема"] == "fum.ожидаемое-состояние-узла.1", "неизвестный expected")
    канон.требовать(all(ожидания[поле] == доверие[поле] for поле in ИДЕНТИЧНОСТЬ), "чужое ожидаемое состояние")
    канон.прочитать_источник(корень, ожидания["основание"], измерения)
    вход = ожидания["предпросмотр"]
    канон.требовать(type(вход) is dict and вход.get("координатор") == доверие["координатор"], "чужой ROOT expected")
    канон.требовать(type(вход.get("исполнители")) is list and all(type(актёр) is dict and актёр.get("снимок") is None
        for актёр in вход["исполнители"]), "expected не включает свежие наблюдения")
    # Прежнее ядро проверяет ACT, решения и поставки; второй реестр не создаётся.
    канон.предпросмотр(вход, корень=корень, каталог_снимков=корень)
    канон.требовать(доставка_гит.гит(корень, "rev-parse", "--verify", ссылка_ветки) == доверие["источник"]["коммит"],
        "поколение изменилось при чтении")
    измерения["git_наносекунды"] = time.monotonic_ns() - начало
    if профиль is not None:
        профиль.update(измерения)
    return {"схема": "fum.загруженные-ожидания-узла.1", "ожидания": ожидания,
        "поколение": copy.deepcopy(доверие["источник"]), "доверие": copy.deepcopy(доверие), "допуск_эффекта": False}


def загрузить_ожидания(доверие, *, корень, профиль=None):
    try:
        return _загрузить_ожидания(доверие, корень=корень, профиль=профиль)
    except канон.приём_делегации.гит.ОшибкаОтчёта as ошибка:
        raise ValueError(str(ошибка)) from ошибка


def проекция_ответа(данные, *, задача, хост):
    """Разбирает сохранённые байты; сам по себе вызов не доказывает свежесть."""
    канон.требовать(type(данные) is bytes and len(данные) <= ПРЕДЕЛ, "payload превышает 64 МиБ")
    try:
        оболочка = компактный.разобрать(данные.decode("utf-8"))
        канон.требовать(type(оболочка) is dict and set(оболочка) <= {"content", "isError"}
            and оболочка.get("isError", False) is False, "ошибочная или неизвестная оболочка MCP")
        части = оболочка["content"]
        канон.требовать(type(части) is list and len(части) == 1, "неполная оболочка MCP")
        часть = части[0]
        канон.поля(часть, {"type", "text"})
        канон.требовать(часть["type"] == "text" and type(часть["text"]) is str, "неизвестная часть MCP")
        ответ = компактный.разобрать(часть["text"])
        канон.поля(ответ, {"schemaVersion", "thread", "page", "turns"})
        канон.требовать(type(ответ["schemaVersion"]) is int and ответ["schemaVersion"] == 1, "неизвестная схема MCP")
        задача_ответа = ответ["thread"]
        канон.требовать(type(задача_ответа) is dict and set(задача_ответа) <=
            {"id", "kind", "hostId", "title", "preview", "status", "cwd", "createdAt", "updatedAt"}
            and задача_ответа.get("id") == задача and задача_ответа.get("hostId") == хост
            and задача_ответа.get("kind") == "codex", "чужой UUID или hostId")
        статус = задача_ответа["status"]
        канон.требовать(type(статус) is dict and set(статус) <= {"type", "activeFlags"}
            and type(статус.get("type")) is str, "неизвестный статус")
        канон.требовать("activeFlags" not in статус or type(статус["activeFlags"]) is list
            and all(type(значение_поля) is str for значение_поля in статус["activeFlags"]), "неверные activeFlags")
        for поле in ("hostId", "title", "preview", "cwd"):
            канон.требовать(поле not in задача_ответа or type(задача_ответа[поле]) is str, "неверное строковое поле задачи")
        for поле in ("createdAt", "updatedAt"):
            канон.требовать(поле not in задача_ответа or задача_ответа[поле] is None
                or type(задача_ответа[поле]) is int, "неверное время задачи")
        страница = ответ["page"]
        канон.поля(страница, {"order", "limit", "nextCursor", "hasMore"})
        канон.требовать(страница["order"] == "newest_first" and type(страница["limit"]) is int
            and страница["limit"] > 0 and type(страница["hasMore"]) is bool
            and (страница["nextCursor"] is None or type(страница["nextCursor"]) is str), "неизвестная страница")
        ходы = ответ["turns"]
        канон.требовать(type(ходы) is list, "неизвестные ходы")
        счётчики = {}
        for ход in ходы:
            канон.поля(ход, компактный.ПОЛЯ_ХОДА)
            канон.требовать(type(ход["id"]) is str and type(ход["status"]) is str and type(ход["items"]) is list,
                "неизвестная форма хода")
            for поле in ("startedAt", "completedAt", "durationMs"):
                канон.требовать(ход[поле] is None or type(ход[поле]) is int, "неверное время хода")
            for элемент in ход["items"]:
                канон.требовать(type(элемент) is dict and type(элемент.get("type")) is str, "неизвестная форма элемента")
                тип = элемент["type"]
                канон.требовать(тип in компактный.ТИПЫ_ЭЛЕМЕНТОВ | ДОПОЛНИТЕЛЬНЫЕ_ТИПЫ, "неизвестный тип элемента")
                if тип == "agentMessage":
                    канон.поля(элемент, {"type", "id", "text", "phase"})
                    канон.требовать(all(type(элемент[значение_поля]) is str for значение_поля in ("id", "text", "phase"))
                        and элемент["phase"] in ("commentary", "final"), "неизвестная форма ответа")
                счётчики[тип] = счётчики.get(тип, 0) + 1
        return {"схема": "fum.проекция-наблюдения-задачи-узла.1", "задача": задача_ответа,
            "страница": страница, "текущий_ход": None if not ходы else компактный.метаданные_хода(ходы[0]),
            "элементы_по_типам": счётчики, "адрес_текущего_хода": None if not ходы else компактный.адрес("turns", 0),
            "неподтверждённые": {поле: "unknown" for поле in ("владелец", "ACT", "модель", "усилие")},
            "полнота_истории": "unknown", "допуск_эффекта": False}
    except (KeyError, TypeError, UnicodeError, RecursionError) as ошибка:
        raise ValueError("повреждённое доступное представление MCP") from ошибка


def кодировать(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":"),
        allow_nan=False).encode("utf-8")


def время_наблюдения():
    return datetime.now(timezone.utc).isoformat(timespec="microseconds").replace("+00:00", "Z")


def прочитать_файл(путь, *, предел, приватный=False):
    """Ограниченное чтение обычного файла без следования ссылкам, включая родителей."""
    путь = Path(путь)
    канон.требовать(путь.is_absolute() and ".." not in путь.parts and путь.name not in ("", "."), "нужен абсолютный путь файла")
    каталог = os.open("/", os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC)
    дескриптор = None
    try:
        for часть in путь.parts[1:-1]:
            следующий = os.open(часть, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=каталог)
            os.close(каталог); каталог = следующий
        дескриптор = os.open(путь.name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=каталог)
        до = os.fstat(дескриптор)
        канон.требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1, "нужен обычный файл без hardlink")
        канон.требовать(not приватный or до.st_mode & 0o077 == 0, "нужен приватный файл")
        канон.требовать(0 <= до.st_size <= предел, "файл превышает предел; усечение запрещено")
        with os.fdopen(дескриптор, "rb", closefd=False) as поток:
            данные = поток.read(до.st_size + 1)
        после = os.fstat(дескриптор)
        канон.требовать(len(данные) <= предел and len(данные) == до.st_size and
            (до.st_size, до.st_mtime_ns, до.st_ctime_ns) == (после.st_size, после.st_mtime_ns, после.st_ctime_ns),
            "файл изменился во время чтения")
        return данные
    finally:
        if дескриптор is not None: os.close(дескриптор)
        os.close(каталог)


class КонтейнерПроцессов:
    """Один существующий контейнер; временные входы не являются вторым хранилищем."""
    def __init__(сам, *, корень_данных, писатель, читатель, корень_репозитория):
        сам.репозиторий = доставка_гит.физический_корень(корень_репозитория)
        сам.корень = канон.физический_путь(корень_данных)
        общий_каталог_гита = Path(доставка_гит.гит(сам.репозиторий, "rev-parse", "--path-format=absolute", "--git-common-dir"))
        for запрет in (сам.репозиторий, общий_каталог_гита.resolve()):
            канон.требовать(not сам.корень.is_relative_to(запрет), "контейнер должен оставаться вне Git")
        канон.требовать(сам.корень.stat().st_mode & 0o077 == 0, "нужен приватный корень контейнера")
        сам.писатель = канон.физический_путь(Path(писатель).parent, Path(писатель).name)
        сам.читатель = канон.физический_путь(Path(читатель).parent, Path(читатель).name)

    def сохранить(сам, описание, данные):
        канон.требовать(type(данные) is bytes and len(данные) <= ПРЕДЕЛ, "payload превышает 64 МиБ")
        with tempfile.TemporaryDirectory(prefix=".вход-", dir=сам.корень) as каталог:
            путь = Path(каталог)
            for имя, содержимое in (("описание.json", кодировать(описание)), ("payload.json", данные)):
                with (путь / имя).open("xb") as поток:
                    os.chmod(путь / имя, 0o600)
                    поток.write(содержимое)
            ответ = subprocess.run([str(сам.писатель), "добавить-описание", str(сам.корень),
                str(путь / "описание.json"), str(путь / "payload.json")], cwd=сам.репозиторий,
                stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60, check=False)
            if ответ.returncode != 0:
                raise OSError("контейнер не подтвердил доставку: " + ответ.stderr.decode("utf-8", errors="replace")[:2000])
            return компактный.разобрать(ответ.stdout)

    def извлечь(сам, идентификатор):
        # Вывод идёт в файл: большой payload не блокирует дочерний процесс на заполненной pipe.
        with tempfile.TemporaryFile(dir=сам.корень) as поток:
            ответ = subprocess.run([str(сам.читатель), "извлечь", str(сам.корень), идентификатор],
                cwd=сам.репозиторий, stdin=subprocess.DEVNULL, stdout=поток, stderr=subprocess.PIPE,
                timeout=60, check=False)
            канон.требовать(ответ.returncode == 0, "не удалось извлечь объект контейнера")
            размер = os.fstat(поток.fileno()).st_size
            канон.требовать(размер <= ПРЕДЕЛ, "извлечённый payload превышает 64 МиБ")
            поток.seek(0)
            данные = поток.read(размер + 1)
            канон.требовать(len(данные) <= ПРЕДЕЛ, "извлечённый payload превышает 64 МиБ")
            return данные


class ЦиклНаблюдения:
    """Конечное адресное чтение. Ни один метод не отправляет команды исполнителям."""
    def __init__(сам, доверие, *, корень, контейнер, история=(), параметры=None):
        сам.корень = доставка_гит.физический_корень(корень)
        сам.доверие = copy.deepcopy(доверие)
        сам.профиль = {имя: 0 for имя in ("вызовов_читающего_адаптера", "send", "create",
            "сериализация_наносекунды", "разбор_наносекунды", "контейнер_наносекунды", "извлечение_наносекунды",
            "повтор_наносекунды", "replay_наносекунды", "сверка_наносекунды", "mcp_наносекунды",
            "полных_байтов", "компактных_байтов")}
        сам.загрузка = загрузить_ожидания(сам.доверие, корень=сам.корень, профиль=сам.профиль)
        сам.цикл = str(uuid4())
        сам.контейнер = контейнер
        сам.параметры = copy.deepcopy(параметры if параметры is not None else {
            "turnLimit": 1, "includeOutputs": True, "maxOutputCharsPerItem": 16000, "cursor": None})
        канон.поля(сам.параметры, {"turnLimit", "includeOutputs", "maxOutputCharsPerItem", "cursor"})
        for поле in ("turnLimit", "maxOutputCharsPerItem"):
            канон.требовать(type(сам.параметры[поле]) is int and сам.параметры[поле] > 0, "неверный предел MCP")
        канон.требовать(type(сам.параметры["includeOutputs"]) is bool and
            (сам.параметры["cursor"] is None or type(сам.параметры["cursor"]) is str), "неверные параметры MCP")
        канон.требовать(len(кодировать({"идентичность": {значение_поля: сам.доверие[значение_поля] for значение_поля in ИДЕНТИЧНОСТЬ},
            "expected": сам.загрузка["поколение"], "параметры": сам.параметры})) <= 48 * 1024,
            "метаданные наблюдения превышают предел до API")
        for актёр in сам.загрузка["ожидания"]["предпросмотр"]["исполнители"]:
            канон.требовать(len(кодировать({"задача": актёр["задача"], "хост": актёр["хост"]})) <= 4096,
                "метаданные адресата превышают предел до API")
        сам.начат = False
        сам.записи = []
        сам.повторы = {}
        сам.история = []
        канон.требовать(type(история) in (list, tuple), "история должна быть конечным перечнем")
        начало = time.monotonic_ns()
        for запись in история:
            копия = copy.deepcopy(запись)
            канон.требовать(type(копия) is dict and копия.get("цикл") != сам.цикл, "история не может быть текущим циклом")
            объект = копия.get("объект")
            if объект is not None:
                данные = сам.контейнер.извлечь(объект["идентификатор"])
                сам.проверить_объект(объект, данные)
                спецификация = компактный.разобрать(base64.b64decode(объект["описание"]["спецификация"], validate=True))
                канон.требовать(all(спецификация.get(поле) == сам.доверие[поле] for поле in ("узел", "репозиторий"))
                    and спецификация["цикл"] == копия["цикл"] and спецификация["запрос"] == копия["запрос"],
                    "чужая привязка исторического объекта")
            копия["свежее_в_этом_цикле"] = False
            сам.история.append(копия)
        сам.профиль["replay_наносекунды"] += time.monotonic_ns() - начало

    @staticmethod
    def проверить_объект(объект, данные):
        канон.поля(объект, {"идентификатор", "описание", "размер", "sha256"})
        канон.требовать(объект["описание"]["идентификатор"] == объект["идентификатор"]
            and type(объект["размер"]) is int and объект["размер"] == len(данные)
            and объект["sha256"] == hashlib.sha256(данные).hexdigest(), "повреждён объект контейнера")

    def наблюдать(сам, читатель, *, источник):
        канон.требовать(not сам.начат and callable(читатель), "цикл уже прочитан; повтор API запрещён")
        канон.строка(источник)
        канон.требовать(len(источник.encode("utf-8")) <= 1024, "источник описания превышает предел до API")
        сам.начат = True
        for актёр in сам.загрузка["ожидания"]["предпросмотр"]["исполнители"]:
            запрос = {"threadId": актёр["задача"], "hostId": актёр["хост"], **сам.параметры}
            if запрос["cursor"] is None:
                del запрос["cursor"]  # Внешний MCP-контракт принимает только строку либо отсутствие.
            запись = {"задача": актёр["задача"], "хост": актёр["хост"], "цикл": сам.цикл,
                "запрос": запрос, "начало": время_наблюдения(), "конец": None, "объект": None,
                "состояние": "unknown", "причина": None, "проекция": None,
                "свежее_в_этом_цикле": False}
            сам.записи.append(запись)
            начало = time.monotonic_ns()
            сам.профиль["вызовов_читающего_адаптера"] += 1
            ошибка_адаптера = None
            try:
                ответ = читатель(copy.deepcopy(запрос))
            except Exception as ошибка:
                ошибка_адаптера = "читающий адаптер не вернул MCP-объект"
                ответ = {"ошибка_читающего_адаптера": {"тип": type(ошибка).__name__, "сообщение": str(ошибка)}}
            запись["конец"] = время_наблюдения()
            сам.профиль["mcp_наносекунды"] += time.monotonic_ns() - начало
            начало = time.monotonic_ns()
            try:
                данные = ответ if type(ответ) is bytes else кодировать(ответ)
                канон.требовать(len(данные) <= ПРЕДЕЛ, "payload превышает 64 МиБ; усечение и повтор API запрещены")
                способ = "полные переданные байты; UTF-8 JSON проверяется после хранения" if type(ответ) is bytes else "json.dumps; UTF-8; sort_keys; separators=(',',':'); ensure_ascii=False; allow_nan=False"
                спецификация = {"схема": "fum.описание-чтения-задачи-узла.1", **{значение_поля: сам.доверие[значение_поля] for значение_поля in ИДЕНТИЧНОСТЬ},
                    "цикл": сам.цикл, "expected": сам.загрузка["поколение"], "запрос": запрос,
                    "начало": запись["начало"], "конец": запись["конец"], "сериализация": способ,
                    "размер": len(данные), "sha256": hashlib.sha256(данные).hexdigest(),
                    "HTTP_байты": "unknown", "полнота_истории": "unknown", "ошибка_API": ошибка_адаптера}
                описание = {"идентификатор": "узел-" + hashlib.sha256(кодировать([сам.доверие["узел"], сам.цикл, актёр["задача"]])).hexdigest(),
                    "тип": "codex-read_thread", "версияСхемы": 1, "источник": источник,
                    "время": запись["конец"], "спецификация": base64.b64encode(кодировать(спецификация)).decode("ascii")}
                канон.требовать(len(кодировать(спецификация)) <= 65536, "слишком большая спецификация наблюдения")
            except (ValueError, TypeError, UnicodeError, RecursionError) as ошибка:
                запись["состояние"], запись["причина"] = "отказ сериализации", str(ошибка)
                continue
            finally:
                сам.профиль["сериализация_наносекунды"] += time.monotonic_ns() - начало
            сам.профиль["полных_байтов"] += len(данные)
            # Эти неизменяемые входы сохраняются до квитанции; retry не получает новых часов или API.
            сам.повторы[актёр["задача"]] = (запись, описание, данные, ошибка_адаптера)
            сам.доставить(актёр["задача"])
        return сам.итог()

    def доставить(сам, задача):
        запись, описание, данные, ошибка_адаптера = сам.повторы[задача]
        начало = time.monotonic_ns()
        try:
            квитанция = сам.контейнер.сохранить(copy.deepcopy(описание), данные)
            канон.поля(квитанция, {"описание", "размер", "хэш"})
            канон.требовать(квитанция["описание"] == описание, "чужое описание в квитанции")
            объект = {"идентификатор": описание["идентификатор"], "описание": copy.deepcopy(описание),
                "размер": квитанция["размер"], "sha256": квитанция["хэш"]}
            сам.проверить_объект(объект, данные)
        except (OSError, ValueError, subprocess.TimeoutExpired) as ошибка:
            запись["состояние"], запись["причина"] = "доставка unknown", str(ошибка)
            return
        finally:
            сам.профиль["контейнер_наносекунды"] += time.monotonic_ns() - начало
        начало = time.monotonic_ns()
        try:
            # Разбор получает точное извлечение после подтверждения существующего контейнера.
            извлечённое = сам.контейнер.извлечь(описание["идентификатор"])
            сам.проверить_объект(объект, извлечённое)
            канон.требовать(извлечённое == данные, "извлечение изменило байты")
            запись["объект"] = объект
        except (OSError, ValueError, subprocess.TimeoutExpired) as ошибка:
            запись["состояние"], запись["причина"] = "доставка unknown", str(ошибка)
            return
        finally:
            сам.профиль["извлечение_наносекунды"] += time.monotonic_ns() - начало
        начало = time.monotonic_ns()
        try:
            if ошибка_адаптера is not None:
                raise ValueError(ошибка_адаптера)
            проекция = проекция_ответа(извлечённое, задача=задача, хост=запись["хост"])
            компактных_байтов = len(кодировать(проекция))
            запись["проекция"] = проекция
            запись["состояние"], запись["причина"] = "наблюдение сохранено", None
            запись["свежее_в_этом_цикле"] = True
            сам.профиль["компактных_байтов"] += компактных_байтов
        except ValueError as ошибка:
            запись["состояние"], запись["причина"] = "ошибка разбора", str(ошибка)
            запись["проекция"], запись["свежее_в_этом_цикле"] = None, False
        finally:
            сам.профиль["разбор_наносекунды"] += time.monotonic_ns() - начало

    def повторить_доставку(сам, задача):
        канон.требовать(задача in сам.повторы and сам.повторы[задача][0]["состояние"] == "доставка unknown",
            "повтор разрешён только для неизвестной квитанции сохранённых входов")
        начало = time.monotonic_ns()
        сам.доставить(задача)
        сам.профиль["повтор_наносекунды"] += time.monotonic_ns() - начало
        return сам.итог()

    def итог(сам):
        начало = time.monotonic_ns()
        актуально, причина, предпросмотр = True, None, None
        try:
            повтор = загрузить_ожидания(сам.доверие, корень=сам.корень)
            канон.требовать(повтор == сам.загрузка, "изменились привязки expected")
            def читать(задача, хост, измерения):
                запись = next((значение_поля for значение_поля in сам.записи if значение_поля["задача"] == задача and значение_поля["хост"] == хост), None)
                if запись is None or not запись["свежее_в_этом_цикле"]:
                    return {"срез": None, "описание": None}
                проекция = запись["проекция"]
                путь = проекция["задача"].get("cwd")
                if хост == "local" and (путь is None or not Path(путь).is_dir()):
                    запись["состояние"], запись["причина"] = "нет дерева", "локальное дерево из ответа отсутствует; владение API не доказано"
                    return {"срез": None, "описание": None}
                return {"срез": проекция, "описание": {"объект": запись["объект"], "цикл": сам.цикл,
                    "курсор_запроса": запись["запрос"].get("cursor")}}
            предпросмотр = канон.предпросмотр_наблюдений(сам.загрузка["ожидания"]["предпросмотр"],
                корень=сам.корень, читатель_наблюдения=читать)
            # Обнаруживает также дрейф во время самого повторного предпросмотра.
            канон.требовать(загрузить_ожидания(сам.доверие, корень=сам.корень) == сам.загрузка, "поколение изменилось при сверке")
        except ValueError as ошибка:
            актуально, причина, предпросмотр = False, str(ошибка), None
        сам.профиль["сверка_наносекунды"] += time.monotonic_ns() - начало
        return copy.deepcopy({"схема": "fum.состояние-задач-узла.1", "цикл": сам.цикл,
            "ожидания": сам.загрузка["ожидания"], "поколение": сам.загрузка["поколение"],
            "поколение_актуально": актуально, "причина_сверки": причина, "наблюдения": сам.записи,
            "история": сам.история, "предпросмотр": предпросмотр, "профиль": сам.профиль,
            "допуск_эффекта": False, "полнота_истории": "unknown"})


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    for имя in ("корень-репозитория", "доверие", "корень-контейнера", "писатель", "читатель"):
        разбор.add_argument("--" + имя, required=True)
    разбор.add_argument("--история")
    разбор.add_argument("--только-восстановить", action="store_true")
    параметры = разбор.parse_args()
    try:
        корень = Path(параметры.корень_репозитория)
        доверие = компактный.разобрать(прочитать_файл(параметры.доверие, предел=65536).decode("utf-8"))
        история = [] if параметры.история is None else компактный.разобрать(прочитать_файл(параметры.история, предел=ПРЕДЕЛ).decode("utf-8"))
        контейнер = КонтейнерПроцессов(корень_данных=Path(параметры.корень_контейнера),
            писатель=параметры.писатель, читатель=параметры.читатель, корень_репозитория=корень)
        цикл = ЦиклНаблюдения(доверие, корень=корень, контейнер=контейнер, история=история)
        def вывести(значение):
            sys.stdout.buffer.write(кодировать(значение) + b"\n")
            sys.stdout.buffer.flush()
        if параметры.только_восстановить:
            вывести(цикл.итог())
            return 0
        def читать(запрос):
            # Реальный MCP вызывает внешняя среда. Этот процесс только принимает полный ответ.
            вывести({"схема": "fum.запрос-внешнего-чтения.1", "цикл": цикл.цикл, "параметры": запрос})
            передача = компактный.разобрать(sys.stdin.buffer.readline(131073))
            канон.поля(передача, {"цикл", "задача", "файл"})
            канон.требовать(передача["цикл"] == цикл.цикл and передача["задача"] == запрос["threadId"], "чужая передача MCP")
            файл = Path(передача["файл"])
            канон.требовать(файл.is_relative_to(контейнер.корень), "ответ должен быть внутри корня контейнера")
            return прочитать_файл(файл, предел=ПРЕДЕЛ, приватный=True)
        вывести(цикл.наблюдать(читать, источник="внешний инструмент MCP; переданный полный объект"))
        for строка in sys.stdin.buffer:
            команда = компактный.разобрать(строка)
            канон.поля(команда, {"повторить_доставку"})
            вывести(цикл.повторить_доставку(команда["повторить_доставку"]))
        return 0
    except (ValueError, OSError, KeyError) as ошибка:
        print("Не удалось восстановить состояние узла: " + str(ошибка), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(выполнить())

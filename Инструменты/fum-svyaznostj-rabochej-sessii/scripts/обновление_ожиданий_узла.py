def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def прочитать(путь):
    return читатель.прочитать_файл(путь, предел=читатель.ПРЕДЕЛ, приватный=True)


def прочитать_намерение(путь):
    return читатель.прочитать_файл(путь, предел=ПРЕДЕЛ_НАМЕРЕНИЯ, приватный=True)


def приватная_ссылка(описание):
    канон.поля(описание, {'путь', 'хэш'})
    канон.полный_хэш(описание['хэш'])
    данные = прочитать(описание['путь'])
    требовать(хэш(данные) == описание['хэш'], 'подменены приватные байты')
    return данные


def источник(корень, описание):
    return канон.прочитать_источник(корень, описание,
        {'прочитано_байтов': 0, 'чтений_git_источников': 0})


def объект(корень, коммит_объекта, имя, /):
    сырые = гит.выполнить(корень, 'ls-tree', '-z', коммит_объекта, '--', имя).stdout
    записи = [з for з in сырые.split(b'\0') if з]
    требовать(len(записи) == 1, 'нет единственного blob expected')
    поля, путь = записи[0].split(b'\t', 1)
    режим, тип, идентификатор_объекта = поля.split()
    требовать(путь.decode() == имя and тип == b'blob' and режим == b'100644', 'expected должен быть обычным blob0644')
    return идентификатор_объекта.decode()


def проверить_кандидат(данные, идентичность, корень):
    требовать(type(данные) is bytes and len(данные) <= читатель.ПРЕДЕЛ, 'слишком большой кандидат')
    значение = читатель.проверить_байты_ожиданий(данные, идентичность, корень=корень)
    требовать(значение['предпросмотр']['полнота_перечня'] is False,
        'expected не доказывает полноту перечня')
    return значение


def состав_писателя(параметры, путь):
    """ACT не расширяет назначение: один expected и закрытый служебный состав."""
    папка = Path(параметры['запрос']).parent
    обязательные = {путь, параметры['запрос'], str(папка/'отчёт.md'), параметры['история_модели']}
    служебные = обязательные | {'Журнал/README.md', 'Индексы/markdown-файлы-по-времени-редактирования.md'}
    цели = set(параметры['разрешённые_цели'])
    for цель in цели - служебные:
        адрес = Path(цель)
        требовать(адрес.parent == папка/'материалы/запуски-проверок'
            and re.fullmatch(r'[1-9][0-9]*_[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\.json', адрес.name),
            'состав писателя содержит дополнительную предметную цель')
    требовать(обязательные <= цели, 'состав писателя не содержит обязательные материалы этапа')
    return цели


def проверить_индекс_писателя(корень, параметры, путь):
    цели = состав_писателя(параметры, путь)
    изменённые = {п.decode() for п in гит.выполнить(корень,
        'diff', '--cached', '--no-renames', '--name-only', '-z').stdout.split(b'\0') if п}
    требовать(изменённые <= цели, 'состав писателя: дополнительный файл в индексе')


def заголовок(вход, *, новый_эффект=True):
    новый = вход.get('схема') == 'fum.обновление-ожиданий-узла.2'
    канон.поля(вход, {'схема', 'операция', 'корень', 'ветка', 'исполнитель', 'путь',
        'доверие', 'первое_создание', 'акт', 'назначение', 'решение', 'контроль',
        'кандидат', 'параметры', 'каталог_операции'} | ({'полномочия_узла'} if новый else set()))
    требовать(новый or вход['схема'] == 'fum.обновление-ожиданий-узла.1', 'неизвестный вход писателя')
    канон.идентичность(вход['операция']); канон.идентичность(вход['исполнитель'])
    требовать(os.environ.get('CODEX_THREAD_ID') == вход['исполнитель'], 'чужой native UUID среды')
    корень = гит.физический_корень(вход['корень'])
    канон.относительный_путь(вход['путь'])
    обычное.проверить_область(корень, [вход['путь']], [вход['путь']])
    выбор = None
    if новый:
        # Независимо выбранный ROOT ACT читается до раннего Git-допуска.
        акт = обычное.прочитать_акт(корень, вход['акт'], новый_эффект=новый_эффект)
        требовать(акт['схема'] == 'fum.поручение-дочерней-контрольной-точки.2'
            and акт['полномочия_узла'] == вход['полномочия_узла'], 'копия полномочий отличается от ROOT ACT')
        выбор = акт['полномочия_узла']
    else:
        требовать(type(вход['ветка']) is str and вход['ветка'].startswith('refs/heads/codex/'), 'нужен собственный codex ref')
    снимок = гит.снимок(корень, вход['исполнитель'], вход['ветка'], выбор, новый_эффект=новый_эффект)
    каталог = канон.физический_путь(вход['каталог_операции'])
    требовать(stat.S_IMODE(каталог.stat().st_mode) == 0o700 and каталог.stat().st_uid == os.getuid(),
        'нужен собственный каталог0700')
    требовать(not каталог.is_relative_to(корень) and not any(os.path.lexists(п / '.git')
        for п in (каталог, *каталог.parents)), 'каталог операции должен быть вне Git')
    return корень, снимок, каталог


def проверить_привязку_подготовки(корень, вход, параметры):
    требовать(параметры['корень'] == str(корень) and параметры['ветка'] == вход['ветка']
        and параметры['исполнитель'] == вход['исполнитель'], 'чужая подготовка писателя')


def проверить_назначение(корень, вход, *, новый_эффект=True):
    """Закреплённый Git-blob и физическая привязка, включая читающий повтор."""
    назначение = канон.разобрать(источник(корень, вход['назначение']))
    требовать(type(назначение) is dict, 'назначение ROOT должно быть JSON-объектом')
    поля = {'схема', 'операция', 'ветка', 'путь', 'исполнитель', 'акт', 'решение',
        'контроль', 'доверие', 'первое_создание', 'хэш_кандидата'} | читатель.ИДЕНТИЧНОСТЬ
    if назначение.get('схема') == 'fum.назначение-писателя-ожиданий.1':
        требовать(вход['схема'] == 'fum.обновление-ожиданий-узла.1', 'смешаны старое и state назначения')
        канон.поля(назначение, поля | {'корень'})
        требовать(назначение['корень'] == вход['корень'], 'назначение расходится с входом: корень')
    elif назначение.get('схема') in {'fum.назначение-писателя-ожиданий.2', 'fum.назначение-писателя-ожиданий.3'}:
        новое = назначение.get('схема') == 'fum.назначение-писателя-ожиданий.3'
        требовать(новое == (вход['схема'] == 'fum.обновление-ожиданий-узла.2'), 'смешаны старое и state назначения')
        канон.поля(назначение, поля | {'хэш_корня'} | ({'полномочия_узла'} if новое else set()))
        канон.полный_хэш(назначение['хэш_корня'])
        # Path может убрать ./ либо лишний /; версия .2 принимает только точную строку.
        требовать(вход['корень'] == str(корень), 'неканоническая строка физического корня')
        требовать(назначение['хэш_корня'] == хэш(str(корень).encode('utf-8')),
            'назначение содержит другой хэш физического корня')
        if новое:
            import полномочия_ветки_состояния_узла as полномочия
            акт = обычное.прочитать_акт(корень, вход['акт'], новый_эффект=новый_эффект)
            требовать(назначение['полномочия_узла'] == вход['полномочия_узла'] == акт['полномочия_узла'],
                'назначение не соответствует независимому ACT полномочий')
            проверенные = полномочия.проверить_акт(корень, акт, новый_эффект=новый_эффект)
            требовать(all(назначение[э] == проверенные[э] for э in читатель.ИДЕНТИЧНОСТЬ)
                and назначение['путь'] == проверенные['путь'], 'подменены ID узла или expected назначения')
    else:
        raise ValueError('неизвестная схема назначения ROOT')
    for поле in ('операция', 'ветка', 'путь', 'исполнитель', 'акт', 'решение', 'контроль', 'доверие', 'первое_создание'):
        требовать(назначение[поле] == вход[поле], 'назначение расходится с входом: ' + поле)
    требовать(назначение['координатор'] == вход['акт']['координатор']
        and назначение['владелец'] == вход['исполнитель'], 'чужой владелец/ROOT назначения')
    for поле in читатель.ИДЕНТИЧНОСТЬ: канон.строка(назначение[поле])
    требовать(назначение['хэш_кандидата'] == вход['кандидат']['хэш'], 'ROOT не выбрал хэш кандидата')
    return назначение


def проверить(вход, *, установлен=False, индекс_готов=False):
    корень, снимок, каталог = заголовок(вход)
    параметры = канон.разобрать(приватная_ссылка(вход['параметры']))
    схема = 'fum.создание-коммита.8' if вход['схема'] == 'fum.обновление-ожиданий-узла.2' else 'fum.создание-коммита.7'
    требовать(параметры.get('схема') == схема, 'нужна соответствующая штатная .7 или state .8')
    обычное.проверить(параметры, вход['акт'])
    проверить_привязку_подготовки(корень, вход, параметры)
    состав_писателя(параметры, вход['путь'])
    требовать(вход['путь'] in параметры['разрешённые_цели'], 'файл не разрешён maker')
    акт = обычное.прочитать_акт(корень, вход['акт'])
    обычное.проверить_область(корень, акт['область'], [вход['путь']])
    назначение = проверить_назначение(корень, вход)
    решение = канон.разобрать(источник(корень, вход['решение']))
    канон.решение_координатора(решение)
    требовать(решение['координатор'] == назначение['координатор']
        and решение['задача'] == решение['владелец'] == вход['исполнитель']
        and решение['поручение'] == вход['акт'], 'чужое разрешающее решение ROOT')
    требовать(решение['состояние'] == 'открыт' and решение['ожидание'] is None
        and решение['результат'] is None and all(с == 'не было' for с in решение['эффекты'].values()),
        'ROOT не допускает нового эффекта')
    контроль = вход['контроль']; канон.поля(контроль, {'ветка', 'коммит'})
    канон.полный_хэш(контроль['коммит'], 40)
    требовать(type(контроль['ветка']) is str and контроль['ветка'].startswith('refs/heads/'), 'нужен полный контрольный ref')
    гит.выполнить(корень, 'check-ref-format', контроль['ветка'])
    требовать(гит.гит(корень, 'rev-parse', '--verify', контроль['ветка']) == контроль['коммит'],
        'изменилось контрольное поколение ROOT')
    данные = приватная_ссылка(вход['кандидат'])
    требовать(хэш(данные) == назначение['хэш_кандидата'], 'ROOT не выбрал эти байты кандидата')
    кандидат = проверить_кандидат(данные, назначение, корень)
    цель = корень / вход['путь']
    if вход['доверие'] is not None:
        требовать(вход['первое_создание'] is None, 'смешаны создание и обновление')
        доверие = вход['доверие']
        читатель.загрузить_ожидания(доверие, корень=корень)
        требовать(доверие['ref'] == вход['ветка'] and доверие['источник']['путь'] == вход['путь']
            and all(доверие[п] == назначение[п] for п in читатель.ИДЕНТИЧНОСТЬ), 'чужое прежнее доверие')
        прежние = источник(корень, доверие['источник']); база = доверие['источник']['коммит']
        требовать(цель.exists(), 'прежний файл исчез')
    else:
        первое = вход['первое_создание']
        канон.поля(первое, {'коммит'} | читатель.ИДЕНТИЧНОСТЬ)
        требовать(all(первое[п] == назначение[п] for п in читатель.ИДЕНТИЧНОСТЬ), 'чужое первое создание')
        канон.полный_хэш(первое['коммит'], 40); база = первое['коммит']; прежние = None
        требовать(not гит.выполнить(корень, 'ls-tree', '-z', база, '--', вход['путь']).stdout,
            'первый файл уже существует в Git')
    требовать(снимок['коммит'] == база == параметры['исходный_коммит']
        and параметры['родители'] == [база], 'дрейф исходного HEAD')
    гит.поддержанное_дерево(корень, база)
    if os.path.lexists(цель):
        фактические = читатель.прочитать_файл(цель, предел=читатель.ПРЕДЕЛ)
        требовать(фактические == прежние or установлен and фактические == данные, 'checkout не равен разрешённым байтам')
    else: требовать(прежние is None, 'прежний файл отсутствует')
    требовать(not гит.служебные_состояния(корень), 'активная Git-операция')
    for имя in ('MERGE_HEAD', 'CHERRY_PICK_HEAD', 'REVERT_HEAD', 'rebase-merge', 'rebase-apply',
            'sequencer', 'BISECT_START', 'index.lock', 'MERGE_AUTOSTASH'):
        требовать(not os.path.lexists(гит.гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', имя)),
            'существует служебная запись Git: ' + имя)
    if not индекс_готов:
        требовать(not гит.выполнить(корень, 'diff', '--cached', '--name-only', '-z').stdout, 'чужой индекс до установки')
    else: проверить_индекс_писателя(корень, параметры, вход['путь'])
    требовать(гит.снимок(корень, вход['исполнитель'], вход['ветка'], вход.get('полномочия_узла')) == снимок
        and гит.гит(корень, 'rev-parse', '--verify', контроль['ветка']) == контроль['коммит'], 'дрейф во время проверки')
    return корень, параметры, данные, прежние, кандидат


def план(вход):
    корень, параметры, данные, прежние, кандидат = проверить(вход)
    разница = ''.join(difflib.unified_diff((прежние or b'').decode().splitlines(keepends=True),
        данные.decode().splitlines(keepends=True), fromfile='прежнее', tofile='кандидат'))
    return {'схема': 'fum.план-обновления-ожиданий.1', 'хэш_входа': хэш(кодировать(вход)),
        'хэш_прежнего': None if прежние is None else хэш(прежние), 'хэш_кандидата': хэш(данные),
        'прежний_объект': None if прежние is None else объект(корень, параметры['исходный_коммит'], вход['путь']),
        'исходное_дерево': гит.гит(корень, 'rev-parse', параметры['исходный_коммит']+'^{tree}'),
        'исходный_коммит': параметры['исходный_коммит'], 'разница': разница, 'допуск_эффекта': False}


def установить_файл(цель, данные, режим):
    """Атомарная замена и fsync каталога; родители проверены перед эффектом."""
    дескриптор, имя = tempfile.mkstemp(prefix='.expected-', dir=цель.parent)
    try:
        with os.fdopen(дескриптор, 'wb') as поток:
            os.fchmod(поток.fileno(), режим); поток.write(данные); поток.flush(); os.fsync(поток.fileno())
        os.replace(имя, цель)
        каталог = os.open(цель.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try: os.fsync(каталог)
        finally: os.close(каталог)
    finally:
        if os.path.exists(имя): os.unlink(имя)


def сохранить(путь, значение):
    установить_файл(путь, кодировать(значение), 0o600)


ВЫХОДЫ_ПОДГОТОВКИ = ('сообщение', 'подготовка', 'квитанция')
ПОЛЯ_НАМЕРЕНИЯ = {'схема', 'вход', 'хэш_входа', 'план', 'кандидат', 'прежнее',
    'стадия', 'хэш_подготовки', 'проверки'}


def неизменяемые_байты(путь, данные):
    """Одноимённый архив никогда не заменяется, даже после перерыва."""
    if os.path.lexists(путь):
        требовать(прочитать_намерение(путь) == данные, 'неполный или изменённый архив; исход unknown')
    else:
        требовать(len(данные) <= ПРЕДЕЛ_НАМЕРЕНИЯ, 'архив превышает предел')
        установить_файл(путь, данные, 0o600)
    return {'путь': str(путь), 'хэш': хэш(данные)}


def прочитать_архив(ссылка):
    канон.поля(ссылка, {'путь', 'хэш'})
    канон.полный_хэш(ссылка['хэш'])
    данные = прочитать_намерение(ссылка['путь'])
    требовать(хэш(данные) == ссылка['хэш'], 'изменён архив переподготовки')
    return данные


def синхронизировать(пути):
    """Creator синхронизирует файлы; переход также закрепляет их каталоги."""
    каталоги = set()
    for путь in map(Path, пути):
        канон.физический_путь(путь.parent)
        дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
        try:
            требовать(stat.S_ISREG(os.fstat(дескриптор).st_mode), 'синхронизируется не обычный файл')
            os.fsync(дескриптор)
        finally: os.close(дескриптор)
        каталоги.add(путь.parent)
    for каталог in sorted(каталоги):
        дескриптор = os.open(каталог, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try: os.fsync(дескриптор)
        finally: os.close(дескриптор)


def параметры_переподготовки(вход, новые, *, новый_эффект=True):
    прежние = канон.разобрать(приватная_ссылка(вход['параметры']))
    параметры = канон.разобрать(приватная_ссылка(новые))
    требовать(новые['путь'] != вход['параметры']['путь'], 'новая .7 имеет прежний адрес')
    требовать(set(параметры) == set(прежние) and параметры.get('схема') == прежние.get('схема')
        and параметры.get('схема') in {'fum.создание-коммита.7', 'fum.создание-коммита.8'}
        and all(параметры[п] == прежние[п] for п in прежние if п not in ВЫХОДЫ_ПОДГОТОВКИ),
        'переподготовка меняет основание или неизменяемые поля .7')
    выходы = [коммит.путь(параметры[п], приватный=True) for п in ВЫХОДЫ_ПОДГОТОВКИ]
    защищённые = {Path(прежние[п]) for п in ВЫХОДЫ_ПОДГОТОВКИ} | {
        Path(вход['параметры']['путь']), Path(новые['путь']), Path(вход['кандидат']['путь']),
        Path(прежние['кэш_модели']), Path(прежние['источник_модели']),
        Path(вход['корень']) / прежние['история_модели'], Path(вход['корень']) / вход['путь']}
    каталог = Path(вход['каталог_операции'])
    требовать(len(set(выходы)) == 3 and not set(выходы).intersection(защищённые)
        and all(п != каталог / 'намерение.json' and not п.is_relative_to(каталог / 'переподготовка')
            for п in выходы), 'новые выходы пересекают прежние свидетельства')
    обычное.проверить(параметры, вход['акт'], новый_эффект=новый_эффект)
    return прежние, параметры


def проверить_модель_подготовки(вход, параметры, п):
    """Полное последнее наблюдение непосредственно перед новым эффектом."""
    модель = коммит.наблюдать_модель(параметры, без_записи=True)
    история = читатель.прочитать_файл(Path(вход['корень']) / параметры['история_модели'],
        предел=читатель.ПРЕДЕЛ)
    курсор = канон.разобрать(прочитать(параметры['кэш_модели']))
    требовать(not курсор['данные']['подготовлено']
        and курсор['данные']['история'] == канон.разобрать(история), 'неполная история или курсор; исход unknown')
    требовать(модель['последнее'] == п['модель'] and модель['число_наблюдений'] == п['наблюдений']
        and хэш(история) == п['история_sha256'] == модель['история_sha256'], 'свежая подготовка модели изменилась')


def проверить_идентичности_переподготовки(вход, исходная, новая=None):
    """Прежняя genuine .9 закрепляет identity и буквальный набор явных дат."""
    автор = коммит.идентичность(Path(вход['корень']), 'GIT_AUTHOR_IDENT')
    коммиттер = коммит.идентичность(Path(вход['корень']), 'GIT_COMMITTER_IDENT')
    требовать(автор[1] == исходная['исходный_автор'][1]
        and коммиттер[:2] == исходная['исходный_коммиттер'][:2]
        and коммит.явные_даты() == исходная['явные_даты'],
        'изменились identity или явные даты прежней .9')
    if новая is not None:
        требовать(новая['исходный_автор'][1] == исходная['исходный_автор'][1]
            and новая['исходный_коммиттер'][:2] == исходная['исходный_коммиттер'][:2]
            and новая['явные_даты'] == исходная['явные_даты'],
            'новая .9 меняет identity или явные даты прежней .9')


def проверить_новую_подготовку(вход, параметры, исходная):
    """Настоящий ordinary guard и свежая полная модель, без готовности к Git."""
    сырые = прочитать(параметры['подготовка'])
    п, _ = коммит.прочитать_подготовку_готовности(Path(параметры['подготовка']),
        доверенное_поручение=вход['акт'])
    требовать(п == канон.разобрать(сырые) and сырые == прочитать(параметры['подготовка'])
        and п['параметры'] == параметры, 'чужая или изменённая свежая .9')
    требовать(коммит.команды(параметры) == п['команды'], 'изменились первичные команды')
    сообщение = прочитать(параметры['сообщение'])
    требовать(хэш(сообщение) == п['сообщение_sha256'], 'изменено новое сообщение')
    проверить_модель_подготовки(вход, параметры, п)
    требовать(коммит.составить_имя(параметры['имя_автора'], п['модель']) == п['имя_автора']
        and коммит.явные_даты() == п['явные_даты'], 'изменились модель автора или явные даты')
    автор = коммит.идентичность(Path(вход['корень']), 'GIT_AUTHOR_IDENT')
    коммиттер = коммит.идентичность(Path(вход['корень']), 'GIT_COMMITTER_IDENT')
    требовать(автор[1] == п['исходный_автор'][1] and коммиттер[:2] == п['исходный_коммиттер'][:2],
        'изменились исходные identity')
    проверить_идентичности_переподготовки(вход, исходная, п)
    return п


def свидетельства_переподготовки(вход, намерение, путь, прежние, новые):
    каталог = Path(вход['каталог_операции']) / 'переподготовка'
    сырые = {'вход.json': кодировать(вход), 'намерение-привязки.json': прочитать_намерение(путь),
        'намерение-внешнее.json': прочитать_намерение(Path(вход['каталог_операции']) / 'намерение.json'),
        'параметры.json': приватная_ссылка(вход['параметры']),
        'подготовка.json': прочитать(прежние['подготовка']), 'сообщение.txt': прочитать(прежние['сообщение']),
        'история-модели.json': читатель.прочитать_файл(Path(вход['корень']) / прежние['история_модели'],
            предел=читатель.ПРЕДЕЛ), 'курсор-модели.json': прочитать(прежние['кэш_модели'])}
    п, _ = коммит.прочитать_подготовку_готовности(Path(прежние['подготовка']), доверенное_поручение=вход['акт'])
    требовать(п == канон.разобрать(сырые['подготовка.json'])
        and п['параметры'] == прежние and хэш(сырые['сообщение.txt']) == п['сообщение_sha256']
        and хэш(сырые['история-модели.json']) == п['история_sha256'], 'неполная прежняя подготовка; исход unknown')
    курсор = канон.разобрать(сырые['курсор-модели.json'])
    требовать(not курсор['данные']['подготовлено']
        and курсор['данные']['история'] == канон.разобрать(сырые['история-модели.json'])
        and курсор['данные']['история']['последнее'] == п['модель']
        and курсор['данные']['история']['число_наблюдений'] == п['наблюдений'],
        'несогласованные прежние история и курсор')
    # Импортёр проверяет исходный inode, префикс, подпись и реализацию курсора.
    коммит.наблюдать_модель(прежние, без_записи=True)
    проверить_идентичности_переподготовки(вход, п)
    ожидаемое = {**намерение, 'стадия': 'намерение', 'хэш_подготовки': None, 'проверки': None}
    требовать(сырые['намерение-внешнее.json'] == кодировать(ожидаемое), 'изменено внешнее намерение')
    требовать(прочитать(прежние['подготовка']) == сырые['подготовка.json'],
        'изменены прежние RAW после подлинного чтения')
    if not os.path.lexists(каталог):
        каталог.mkdir(mode=0o700)
        синхронизировать([Path(вход['каталог_операции']) / 'намерение.json'])
    канон.физический_путь(каталог)
    требовать(stat.S_IMODE(каталог.stat().st_mode) == 0o700, 'неприватный архив переподготовки')
    архив = {'схема': 'fum.исходные-свидетельства-переподготовки.1', 'хэш_входа': намерение['хэш_входа'],
        'новые_параметры': новые, 'файлы': {имя: неизменяемые_байты(каталог / имя, данные)
            for имя, данные in сырые.items()}}
    ссылка = неизменяемые_байты(каталог / 'архив.json', кодировать(архив))
    # До fence ни история, ни прежняя подготовка не должны измениться.
    требовать(прочитать(прежние['кэш_модели']) == сырые['курсор-модели.json']
        and читатель.прочитать_файл(Path(вход['корень']) / прежние['история_модели'],
            предел=читатель.ПРЕДЕЛ) == сырые['история-модели.json'], 'дрейф во время архивирования')
    return ссылка


def сверить_архив_переподготовки(вход, намерение, прежние):
    переход = намерение['переподготовка']
    канон.поля(переход, {'схема', 'параметры', 'архив', 'запечатано'})
    требовать(переход['схема'] == 'fum.переход-переподготовки-ожиданий.1', 'неизвестный переход')
    архив = канон.разобрать(прочитать_архив(переход['архив']))
    канон.поля(архив, {'схема', 'хэш_входа', 'новые_параметры', 'файлы'})
    имена = {'вход.json', 'намерение-привязки.json', 'намерение-внешнее.json', 'параметры.json',
        'подготовка.json', 'сообщение.txt', 'история-модели.json', 'курсор-модели.json'}
    требовать(архив['схема'] == 'fum.исходные-свидетельства-переподготовки.1'
        and архив['хэш_входа'] == намерение['хэш_входа'] and архив['новые_параметры'] == переход['параметры']
        and set(архив['файлы']) == имена, 'чужое происхождение архива')
    каталог = Path(вход['каталог_операции']) / 'переподготовка'
    требовать(Path(переход['архив']['путь']) == каталог / 'архив.json', 'чужой каталог архива')
    данные = {}
    for имя, ссылка in архив['файлы'].items():
        требовать(Path(ссылка['путь']) == каталог / имя, 'чужой адрес свидетельства')
        данные[имя] = прочитать_архив(ссылка)
    исходное = канон.разобрать(данные['намерение-привязки.json'])
    канон.поля(исходное, ПОЛЯ_НАМЕРЕНИЯ)
    требовать(исходное['схема'] == 'fum.намерение-обновления-ожиданий.1'
        and исходное['стадия'] == 'установлено' and исходное['хэш_подготовки'] is None
        and исходное['проверки'] is None and all(исходное[п] == намерение[п]
            for п in исходное if п not in ('схема', 'стадия', 'хэш_подготовки', 'проверки')),
        'изменено исходное намерение')
    требовать(данные['вход.json'] == кодировать(вход)
        and данные['параметры.json'] == приватная_ссылка(вход['параметры'])
        and данные['подготовка.json'] == прочитать(прежние['подготовка'])
        and данные['сообщение.txt'] == прочитать(прежние['сообщение'])
        and данные['намерение-внешнее.json'] == прочитать_намерение(Path(вход['каталог_операции']) / 'намерение.json'),
        'изменены прежние RAW переподготовки')
    return данные



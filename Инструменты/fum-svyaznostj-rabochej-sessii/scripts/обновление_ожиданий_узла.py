ПРЕДЕЛ_НАМЕРЕНИЯ = 8 * читатель.ПРЕДЕЛ


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def прочитать(путь):
    return читатель.прочитать_файл(путь, предел=читатель.ПРЕДЕЛ, приватный=True)


def прочитать_намерение(путь):
    return читатель.прочитать_файл(путь, предел=ПРЕДЕЛ_НАМЕРЕНИЯ, приватный=True)


def приватная_ссылка(описание):
    канон.поля(описание, {'путь', 'хэш'})
    канон.полный_хэш(описание['хэш'])
    данные = прочитать(описание['путь'])
    требовать(хэш(данные) == описание['хэш'], 'подменены приватные байты')
    return данные


def источник(корень, описание):
    return канон.прочитать_источник(корень, описание,
        {'прочитано_байтов': 0, 'чтений_git_источников': 0})


def объект(корень, коммит_объекта, имя, /):
    сырые = гит.выполнить(корень, 'ls-tree', '-z', коммит_объекта, '--', имя).stdout
    записи = [з for з in сырые.split(b'\0') if з]
    требовать(len(записи) == 1, 'нет единственного blob expected')
    поля, путь = записи[0].split(b'\t', 1)
    режим, тип, идентификатор_объекта = поля.split()
    требовать(путь.decode() == имя and тип == b'blob' and режим == b'100644', 'expected должен быть обычным blob0644')
    return идентификатор_объекта.decode()


def проверить_кандидат(данные, идентичность, корень):
    требовать(type(данные) is bytes and len(данные) <= читатель.ПРЕДЕЛ, 'слишком большой кандидат')
    значение = читатель.проверить_байты_ожиданий(данные, идентичность, корень=корень)
    требовать(значение['предпросмотр']['полнота_перечня'] is False,
        'expected не доказывает полноту перечня')
    return значение


def состав_писателя(параметры, путь):
    """ACT не расширяет назначение: один expected и закрытый служебный состав."""
    папка = Path(параметры['запрос']).parent
    обязательные = {путь, параметры['запрос'], str(папка/'отчёт.md'), параметры['история_модели']}
    служебные = обязательные | {'Журнал/README.md', 'Индексы/markdown-файлы-по-времени-редактирования.md'}
    цели = set(параметры['разрешённые_цели'])
    for цель in цели - служебные:
        адрес = Path(цель)
        требовать(адрес.parent == папка/'материалы/запуски-проверок'
            and re.fullmatch(r'[1-9][0-9]*_[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\.json', адрес.name),
            'состав писателя содержит дополнительную предметную цель')
    требовать(обязательные <= цели, 'состав писателя не содержит обязательные материалы этапа')
    return цели


def проверить_индекс_писателя(корень, параметры, путь):
    цели = состав_писателя(параметры, путь)
    изменённые = {п.decode() for п in гит.выполнить(корень,
        'diff', '--cached', '--no-renames', '--name-only', '-z').stdout.split(b'\0') if п}
    требовать(изменённые <= цели, 'состав писателя: дополнительный файл в индексе')


def заголовок(вход):
    канон.поля(вход, {'схема', 'операция', 'корень', 'ветка', 'исполнитель', 'путь',
        'доверие', 'первое_создание', 'акт', 'назначение', 'решение', 'контроль',
        'кандидат', 'параметры', 'каталог_операции'})
    требовать(вход['схема'] == 'fum.обновление-ожиданий-узла.1', 'неизвестный вход писателя')
    канон.идентичность(вход['операция']); канон.идентичность(вход['исполнитель'])
    требовать(os.environ.get('CODEX_THREAD_ID') == вход['исполнитель'], 'чужой native UUID среды')
    корень = гит.физический_корень(вход['корень'])
    канон.относительный_путь(вход['путь'])
    обычное.проверить_область(корень, [вход['путь']], [вход['путь']])
    требовать(type(вход['ветка']) is str and вход['ветка'].startswith('refs/heads/codex/'), 'нужен собственный codex ref')
    снимок = гит.снимок(корень, вход['исполнитель'], вход['ветка'])
    каталог = канон.физический_путь(вход['каталог_операции'])
    требовать(stat.S_IMODE(каталог.stat().st_mode) == 0o700 and каталог.stat().st_uid == os.getuid(),
        'нужен собственный каталог0700')
    требовать(not каталог.is_relative_to(корень) and not any(os.path.lexists(п / '.git')
        for п in (каталог, *каталог.parents)), 'каталог операции должен быть вне Git')
    return корень, снимок, каталог


def проверить(вход, *, установлен=False, индекс_готов=False):
    корень, снимок, каталог = заголовок(вход)
    параметры = канон.разобрать(приватная_ссылка(вход['параметры']))
    требовать(параметры.get('схема') == 'fum.создание-коммита.7', 'нужен штатный вход .7')
    обычное.проверить(параметры, вход['акт'])
    требовать(параметры['корень'] == str(корень) and параметры['ветка'] == вход['ветка']
        and параметры['исполнитель'] == вход['исполнитель'], 'чужая подготовка писателя')
    состав_писателя(параметры, вход['путь'])
    требовать(вход['путь'] in параметры['разрешённые_цели'], 'файл не разрешён maker')
    акт = обычное.прочитать_акт(корень, вход['акт'])
    обычное.проверить_область(корень, акт['область'], [вход['путь']])
    назначение = канон.разобрать(источник(корень, вход['назначение']))
    канон.поля(назначение, {'схема', 'операция', 'корень', 'ветка', 'путь', 'исполнитель',
        'акт', 'решение', 'контроль', 'доверие', 'первое_создание', 'хэш_кандидата'} | читатель.ИДЕНТИЧНОСТЬ)
    требовать(назначение['схема'] == 'fum.назначение-писателя-ожиданий.1', 'нет отдельного назначения ROOT')
    for поле in ('операция', 'корень', 'ветка', 'путь', 'исполнитель', 'акт', 'решение', 'контроль', 'доверие', 'первое_создание'):
        требовать(назначение[поле] == вход[поле], 'назначение расходится с входом: ' + поле)
    требовать(назначение['координатор'] == вход['акт']['координатор']
        and назначение['владелец'] == вход['исполнитель'], 'чужой владелец/ROOT назначения')
    for поле in читатель.ИДЕНТИЧНОСТЬ: канон.строка(назначение[поле])
    решение = канон.разобрать(источник(корень, вход['решение']))
    канон.решение_координатора(решение)
    требовать(решение['координатор'] == назначение['координатор']
        and решение['задача'] == решение['владелец'] == вход['исполнитель']
        and решение['поручение'] == вход['акт'], 'чужое разрешающее решение ROOT')
    требовать(решение['состояние'] == 'открыт' and решение['ожидание'] is None
        and решение['результат'] is None and all(с == 'не было' for с in решение['эффекты'].values()),
        'ROOT не допускает нового эффекта')
    контроль = вход['контроль']; канон.поля(контроль, {'ветка', 'коммит'})
    канон.полный_хэш(контроль['коммит'], 40)
    требовать(type(контроль['ветка']) is str and контроль['ветка'].startswith('refs/heads/'), 'нужен полный контрольный ref')
    гит.выполнить(корень, 'check-ref-format', контроль['ветка'])
    требовать(гит.гит(корень, 'rev-parse', '--verify', контроль['ветка']) == контроль['коммит'],
        'изменилось контрольное поколение ROOT')
    данные = приватная_ссылка(вход['кандидат'])
    требовать(хэш(данные) == назначение['хэш_кандидата'], 'ROOT не выбрал эти байты кандидата')
    кандидат = проверить_кандидат(данные, назначение, корень)
    цель = корень / вход['путь']
    if вход['доверие'] is not None:
        требовать(вход['первое_создание'] is None, 'смешаны создание и обновление')
        доверие = вход['доверие']
        читатель.загрузить_ожидания(доверие, корень=корень)
        требовать(доверие['ref'] == вход['ветка'] and доверие['источник']['путь'] == вход['путь']
            and all(доверие[п] == назначение[п] for п in читатель.ИДЕНТИЧНОСТЬ), 'чужое прежнее доверие')
        прежние = источник(корень, доверие['источник']); база = доверие['источник']['коммит']
        требовать(цель.exists(), 'прежний файл исчез')
    else:
        первое = вход['первое_создание']
        канон.поля(первое, {'коммит'} | читатель.ИДЕНТИЧНОСТЬ)
        требовать(all(первое[п] == назначение[п] for п in читатель.ИДЕНТИЧНОСТЬ), 'чужое первое создание')
        канон.полный_хэш(первое['коммит'], 40); база = первое['коммит']; прежние = None
        требовать(not гит.выполнить(корень, 'ls-tree', '-z', база, '--', вход['путь']).stdout,
            'первый файл уже существует в Git')
    требовать(снимок['коммит'] == база == параметры['исходный_коммит']
        and параметры['родители'] == [база], 'дрейф исходного HEAD')
    гит.поддержанное_дерево(корень, база)
    if os.path.lexists(цель):
        фактические = читатель.прочитать_файл(цель, предел=читатель.ПРЕДЕЛ)
        требовать(фактические == прежние or установлен and фактические == данные, 'checkout не равен разрешённым байтам')
    else: требовать(прежние is None, 'прежний файл отсутствует')
    требовать(not гит.служебные_состояния(корень), 'активная Git-операция')
    for имя in ('MERGE_HEAD', 'CHERRY_PICK_HEAD', 'REVERT_HEAD', 'rebase-merge', 'rebase-apply',
            'sequencer', 'BISECT_START', 'index.lock', 'MERGE_AUTOSTASH'):
        требовать(not os.path.lexists(гит.гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', имя)),
            'существует служебная запись Git: ' + имя)
    if not индекс_готов:
        требовать(not гит.выполнить(корень, 'diff', '--cached', '--name-only', '-z').stdout, 'чужой индекс до установки')
    else: проверить_индекс_писателя(корень, параметры, вход['путь'])
    требовать(гит.снимок(корень, вход['исполнитель'], вход['ветка']) == снимок
        and гит.гит(корень, 'rev-parse', '--verify', контроль['ветка']) == контроль['коммит'], 'дрейф во время проверки')
    return корень, параметры, данные, прежние, кандидат


def план(вход):
    корень, параметры, данные, прежние, кандидат = проверить(вход)
    разница = ''.join(difflib.unified_diff((прежние or b'').decode().splitlines(keepends=True),
        данные.decode().splitlines(keepends=True), fromfile='прежнее', tofile='кандидат'))
    return {'схема': 'fum.план-обновления-ожиданий.1', 'хэш_входа': хэш(кодировать(вход)),
        'хэш_прежнего': None if прежние is None else хэш(прежние), 'хэш_кандидата': хэш(данные),
        'прежний_объект': None if прежние is None else объект(корень, параметры['исходный_коммит'], вход['путь']),
        'исходное_дерево': гит.гит(корень, 'rev-parse', параметры['исходный_коммит']+'^{tree}'),
        'исходный_коммит': параметры['исходный_коммит'], 'разница': разница, 'допуск_эффекта': False}


def установить_файл(цель, данные, режим):
    """Атомарная замена и fsync каталога; родители проверены перед эффектом."""
    дескриптор, имя = tempfile.mkstemp(prefix='.expected-', dir=цель.parent)
    try:
        with os.fdopen(дескриптор, 'wb') as поток:
            os.fchmod(поток.fileno(), режим); поток.write(данные); поток.flush(); os.fsync(поток.fileno())
        os.replace(имя, цель)
        каталог = os.open(цель.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try: os.fsync(каталог)
        finally: os.close(каталог)
    finally:
        if os.path.exists(имя): os.unlink(имя)


def сохранить(путь, значение):
    установить_файл(путь, кодировать(значение), 0o600)


@contextlib.contextmanager
def привязка(вход):
    корень, _, каталог = заголовок(вход)
    служебный = канон.физический_путь(гит.гит(корень, 'rev-parse', '--absolute-git-dir'))
    имя = хэш((вход['ветка'] + '\0' + вход['путь']).encode())
    папка = служебный / 'писатель-ожиданий'
    if not os.path.lexists(папка):
        папка.mkdir(mode=0o700)
        дескриптор = os.open(служебный, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try: os.fsync(дескриптор)
        finally: os.close(дескриптор)
    канон.физический_путь(папка)
    требовать(stat.S_IMODE(папка.stat().st_mode) == 0o700, 'неприватная привязка писателя')
    замок = os.open(папка / (имя + '.lock'), os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    try:
        с = os.fstat(замок)
        требовать(stat.S_ISREG(с.st_mode) and с.st_nlink == 1 and stat.S_IMODE(с.st_mode) == 0o600, 'небезопасный замок')
        try: fcntl.flock(замок, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as ошибка: raise ValueError('другой писатель держит файл') from ошибка
        путь = папка / (имя + '.json')
        намерение = канон.разобрать(прочитать_намерение(путь)) if os.path.lexists(путь) else None
        if намерение is not None:
            if намерение['вход'] != вход:
                # Только подтверждённое поколение допускает новую независимую операцию.
                требовать(намерение['стадия'] == 'попытка-коммита', 'прежняя операция запрещает новое UUID/каталог')
                завершённый = подтвердить(намерение['вход'], намерение)
                требовать(вход['доверие'] == завершённый['доверие']
                    and вход['операция'] != намерение['вход']['операция']
                    and вход['назначение'] != намерение['вход']['назначение']
                    and вход['контроль']['коммит'] != намерение['вход']['контроль']['коммит'],
                    'нет нового назначения от подтверждённого поколения')
                проверить(вход)
                архив = папка / (имя + '-' + хэш(кодировать(намерение)) + '.json')
                if os.path.lexists(архив): требовать(прочитать_намерение(архив) == кодировать(намерение), 'архив изменён')
                else: сохранить(архив, намерение)
                намерение = None
            else:
                требовать(намерение['хэш_входа'] == хэш(кодировать(вход)), 'повреждена привязка входа')
        else:
            требовать(not os.path.lexists(каталог / 'намерение.json'), 'утрачена устойчивая привязка; исход unknown')
        yield путь, намерение
    finally: os.close(замок)


def установить(вход, выбранный_план):
    with привязка(вход) as (путь, намерение):
        if намерение is None:
            текущий = план(вход)
            требовать(текущий == выбранный_план, 'план изменился')
            корень, параметры, данные, прежние, _ = проверить(вход)
            требовать(данные != прежние, 'пустое обновление')
            намерение = {'схема': 'fum.намерение-обновления-ожиданий.1', 'вход': copy.deepcopy(вход),
                'хэш_входа': хэш(кодировать(вход)), 'план': текущий,
                'кандидат': base64.b64encode(данные).decode(),
                'прежнее': None if прежние is None else base64.b64encode(прежние).decode(),
                'стадия': 'намерение', 'хэш_подготовки': None, 'проверки': None}
            требовать(len(кодировать(намерение)) <= ПРЕДЕЛ_НАМЕРЕНИЯ, 'намерение превышает отдельный предел')
            сохранить(путь, намерение)
        требовать(намерение['план'] == выбранный_план, 'повтор с другим планом')
        требовать(намерение['стадия'] in ('намерение', 'установлено'), 'попытка Git уже начата; нужен читающий повтор')
        копия = {**намерение, 'стадия': 'намерение', 'хэш_подготовки': None, 'проверки': None}
        внешний = Path(вход['каталог_операции']) / 'намерение.json'
        if os.path.lexists(внешний): требовать(прочитать_намерение(внешний) == кодировать(копия), 'изменена внешняя копия намерения')
        else: сохранить(внешний, копия)
        корень, _, данные, _, _ = проверить(вход, установлен=True)
        требовать(base64.b64decode(намерение['кандидат'], validate=True) == данные, 'подменено намерение')
        цель = корень / вход['путь']
        канон.физический_путь(цель.parent)
        режим = stat.S_IMODE(цель.stat().st_mode) if цель.exists() else 0o644
        требовать(режим == 0o644, 'expected требует обычный режим0644')
        установить_файл(цель, данные, режим)
        намерение['стадия'] = 'установлено'; сохранить(путь, намерение)
        return {'схема': 'fum.установленные-ожидания.1', 'хэш_кандидата': хэш(данные), 'коммит': None}


def подтвердить(вход, намерение):
    """Настоящая квитанция проверяется до допуска прежнего HEAD; никаких эффектов."""
    корень, _, _ = заголовок(вход)
    параметры = канон.разобрать(приватная_ссылка(вход['параметры']))
    обычное.проверить(параметры, вход['акт'], новый_эффект=False)
    цели = состав_писателя(параметры, вход['путь'])
    подготовка = прочитать(параметры['подготовка'])
    требовать(хэш(подготовка) == намерение['хэш_подготовки'], 'подготовка повтора изменена')
    п = канон.разобрать(подготовка)
    требовать(п['схема'] == 'fum.подготовленный-коммит.9' and п['параметры'] == параметры, 'чужая .9')
    требовать(os.path.lexists(параметры['квитанция']), 'нет квитанции; исход процесса unknown, повтор запрещён')
    квитанция = канон.разобрать(прочитать(параметры['квитанция']))
    требовать(квитанция.get('подготовка_sha256') == хэш(подготовка), 'чужая квитанция')
    коммит.сверить_ожидание_квитанции(квитанция, п, параметры)
    итог = коммит.восстановить(корень, квитанция, Path(параметры['квитанция']))
    требовать(итог['родители'] == [параметры['исходный_коммит']], 'неверные родители результата')
    изменённые = {п.decode() for п in гит.выполнить(корень, 'diff-tree', '--no-commit-id',
        '--no-renames', '--name-only', '-r', '-z', параметры['исходный_коммит'], итог['коммит']).stdout.split(b'\0') if п}
    требовать(вход['путь'] in изменённые and изменённые <= цели,
        'состав писателя расходится с конечным коммитом')
    данные = гит.объект_файла(корень, итог['коммит'], вход['путь'])
    сырой_объект = объект(корень, итог['коммит'], вход['путь'])
    требовать(сырой_объект == hashlib.sha1(b'blob '+str(len(данные)).encode()+b'\0'+данные).hexdigest(),
        'сырой blob OID не совпадает с байтами')
    требовать(данные == base64.b64decode(намерение['кандидат'], validate=True)
        and хэш(данные) == вход['кандидат']['хэш'], 'коммит содержит другой expected blob')
    идентичности = {п: канон.разобрать(данные)[п] for п in читатель.ИДЕНТИЧНОСТЬ}
    доверие = {'схема': 'fum.доверие-ожиданиям-узла.1', **идентичности,
        'ref': вход['ветка'], 'источник': {'коммит': итог['коммит'], 'путь': вход['путь'], 'sha256': хэш(данные)}}
    читатель.загрузить_ожидания(доверие, корень=корень)
    return {'схема': 'fum.результат-обновления-ожиданий.1', 'коммит': итог, 'доверие': доверие,
        'доставка': 'unknown', 'отправки': 0, 'создания_чатов': 0}


def повтор(вход):
    # Читающий повтор не создаёт каталог, lock, намерение или новую подготовку.
    корень, _, _ = заголовок(вход)
    папка = Path(гит.гит(корень, 'rev-parse', '--absolute-git-dir')) / 'писатель-ожиданий'
    путь = папка / (хэш((вход['ветка'] + '\0' + вход['путь']).encode()) + '.json')
    намерение = канон.разобрать(прочитать_намерение(путь))
    требовать(намерение['вход'] == вход and намерение['хэш_входа'] == хэш(кодировать(вход)), 'чужой повтор')
    требовать(намерение['стадия'] == 'попытка-коммита', 'коммит ещё не вызван')
    return подтвердить(вход, намерение)


def зафиксировать(вход, необходимые):
    with привязка(вход) as (путь, намерение):
        требовать(намерение is not None, 'нет намерения до эффекта')
        if намерение['стадия'] == 'попытка-коммита': return подтвердить(вход, намерение)
        требовать(намерение['стадия'] == 'установлено', 'файл не установлен')
        корень, параметры, данные, _, _ = проверить(вход, установлен=True, индекс_готов=True)
        требовать(читатель.прочитать_файл(корень / вход['путь'], предел=читатель.ПРЕДЕЛ) == данные, 'потеряна установка')
        подготовка = прочитать(параметры['подготовка']); п = канон.разобрать(подготовка)
        требовать(п.get('схема') == 'fum.подготовленный-коммит.9' and п['параметры'] == параметры, 'нужна точная .9')
        требовать(not os.path.lexists(параметры['квитанция']), 'чужая прежняя квитанция')
        намерение.update(стадия='попытка-коммита', хэш_подготовки=хэш(подготовка), проверки=необходимые)
        сохранить(путь, намерение)
        проверить(вход, установлен=True, индекс_готов=True)
        # Сохраняем прежний creator и добавляем последний читающий допуск у его Git-границ.
        исходный_гит = коммит.гит
        def проверенный_гит(адрес, *аргументы, **настройки):
            if аргументы and аргументы[0] in ('write-tree', 'commit'):
                проверить(вход, установлен=True, индекс_готов=True)
            return исходный_гит(адрес, *аргументы, **настройки)
        коммит.гит = проверенный_гит
        try:
            коммит.создать(Path(параметры['подготовка']), необходимые, доверенное_поручение=вход['акт'])
        finally: коммит.гит = исходный_гит
        return подтвердить(вход, намерение)


def подтвердить_доставку(состояние, удалённый_объект, ожидаемый_объект, /):
    требовать(состояние in ('unknown', 'подтверждён', 'не было'), 'неизвестная доставка')
    канон.полный_хэш(ожидаемый_объект, 40)
    требовать(удалённый_объект == ожидаемый_объект, 'нет точного remote readback; повтор push не разрешён')
    return 'подтверждён'



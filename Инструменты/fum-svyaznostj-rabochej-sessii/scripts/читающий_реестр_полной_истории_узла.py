class Бюджет:
    def __init__(сам, пределы, начало):
        сам.пределы = пределы
        сам.конец = начало + пределы['время_нс']
        сам.прочитано = 0

    def срок(сам):
        старый.требовать(time.perf_counter_ns() < сам.конец,
            'истёк конечный бюджет полного читающего реестра')

    def чтение(сам, размер):
        сам.прочитано += размер
        старый.требовать(сам.прочитано <= сам.пределы['байтов_чтения'],
            'превышен конечный бюджет I/O')
        сам.срок()


class РеестрПолнойИстории(старый._РеестрЦепиЯкорей):
    """Меняются только пределы нового экземпляра; старые классы неизменны."""
    def __init__(сам, источник, координатор, владелец, префиксы, бюджет):
        super().__init__(источник, координатор, владелец, префиксы)
        сам.ПРЕДЕЛ_РАМОК = бюджет.пределы['рамок_на_источник']
        сам.ПРЕДЕЛ_БАЙТОВ = бюджет.пределы['сырых_байтов_на_источник']
        сам.бюджет = бюджет
        сам.байтов_идентификаторов = 0
        сам.сжатий_учтено = 0

    def наблюдать(сам, данные):
        try:
            старый.требовать(type(данные) is bytes
                and len(данные) <= сам.бюджет.пределы['байтов_строки'],
                'превышен конечный бюджет строки')
            return super().наблюдать(данные)
        except BaseException:
            сам.ошибка = сам.копии.ошибка = True
            raise

    def _наблюдать_запись(сам, данные, запись, место=None):
        try:
            return сам._наблюдать_с_ресурсами(данные, запись, место)
        except BaseException:
            сам.ошибка = сам.копии.ошибка = True
            raise

    def завершить(сам, *, _срез=False):
        try:
            сам.бюджет.срок()
            результат = super().завершить(_срез=_срез)
            сам.бюджет.срок()
            return результат
        except BaseException:
            сам.ошибка = сам.копии.ошибка = True
            raise

    def _наблюдать_с_ресурсами(сам, данные, запись, место):
        старый.требовать(len(данные) <= сам.бюджет.пределы['байтов_строки'],
            'превышен конечный бюджет строки')
        прежние = (len(сам.копии.id), len(сам.виденные_обычные_вызовы),
            len(сам.виденные_элементы))
        результат = super()._наблюдать_запись(данные, запись, место)
        if запись['type'] == 'compacted':
            сам.сжатий_учтено += 1
        текущие = (len(сам.копии.id), len(сам.виденные_обычные_вызовы),
            len(сам.виденные_элементы))
        содержимое = запись['payload']
        if текущие[0] > прежние[0]:
            номер = содержимое.get('id', содержимое.get('item', {}).get('id'))
            сам.байтов_идентификаторов += len(номер.encode()) + 64
        if текущие[1] > прежние[1]:
            сам.байтов_идентификаторов += len(содержимое['call_id'].encode()) + 64
        if текущие[2] > прежние[2]:
            сам.байтов_идентификаторов += len(содержимое['item']['id'].encode()) + 64
        пределы = сам.бюджет.пределы
        старый.требовать(sum(текущие) <= пределы['идентификаторов_на_источник']
            and сам.байтов_идентификаторов <= пределы['байтов_идентификаторов'],
            'превышен конечный бюджет глобальных ID')
        старый.требовать(len(сам.вызовы) + len(сам.учёт_элементов)
            <= пределы['незавершённых_вызовов'], 'превышен бюджет pending RPC/MCP')
        старый.требовать(len(сам.управляющие) <= пределы['управляющих_оригиналов']
            and сам.сжатий_учтено <= пределы['сжатий'],
            'превышен бюджет управляющих оригиналов или сжатий')
        сам.бюджет.срок()
        return результат


def _гит_под_сроком(корень, аргументы, бюджет):
    бюджет.срок()
    команда, среда = старый.команда_гит(корень, аргументы)
    ожидание = min(60, (бюджет.конец - time.perf_counter_ns()) / 1000000000)
    try:
        ответ = subprocess.run(команда, env=среда, capture_output=True,
            timeout=max(0.000001, ожидание))
    except subprocess.TimeoutExpired as ошибка:
        raise ValueError('Git-чтение не завершилось в общем бюджете') from ошибка
    бюджет.срок()
    старый.требовать(ответ.returncode == 0, 'не подтверждено контрольное Git-состояние')
    return ответ.stdout


def _прочитать_выбор(корень, выбранный, бюджет=None):
    with старый.НачальныеОбъекты(корень) as объекты:
        остаток = ПРЕДЕЛ_ВЫБОРА_НС if бюджет is None else бюджет.конец - time.perf_counter_ns()
        старый.требовать(остаток > 0, 'истёк бюджет выбора ресурсного документа')
        объекты.конец = time.monotonic() + остаток / 1000000000
        данные = старый.прочитать_источник(корень, выбранный, читатель=объекты)
    if бюджет is not None:
        бюджет.срок()
    return данные


def _контроль(корень, контроль, бюджет):
    старый.поля(контроль, {'ветка', 'коммит'})
    старый.сумма(контроль['коммит'], 40)
    старый.требовать(type(контроль['ветка']) is str
        and контроль['ветка'].startswith('refs/heads/codex/'),
        'нужен независимый контрольный ref codex')
    _гит_под_сроком(корень, ('check-ref-format', контроль['ветка']), бюджет)
    ответ = _гит_под_сроком(корень, ('rev-parse', '--verify', контроль['ветка']), бюджет)
    старый.требовать(ответ == (контроль['коммит'] + '\n').encode(),
        'контрольное поколение отозвано или устарело')


def _ресурс(корень, вход, выбранный, начало):
    старый.выбор(выбранный)
    данные = _прочитать_выбор(корень, выбранный)
    старый.требовать(0 < len(данные) <= ПРЕДЕЛ_ДОКУМЕНТА,
        'превышен размер конечного ресурсного документа')
    ресурс = старый.разобрать_JSON(данные, ПРЕДЕЛ_ДОКУМЕНТА)
    старый.поля(ресурс, {'схема', 'координатор', 'владелец', 'контроль',
        'рождения', 'пределы'})
    старый.требовать(ресурс['схема'] == СХЕМА_РЕСУРСА
        and all(ресурс[ключ] == вход[ключ] for ключ in
            ('координатор', 'владелец', 'контроль')), 'чужой ресурсный документ ROOT')
    старый.поля(ресурс['пределы'], ИМЕНА_ПРЕДЕЛОВ)
    старый.требовать(all(type(число) is int and число > 0
        for число in ресурс['пределы'].values()), 'пределы должны быть конечными положительными целыми')
    старый.требовать(ресурс['пределы']['байтов_строки'] <= старый.ПРЕДЕЛ_НАТИВНОЙ_СТРОКИ,
        'новая версия сохраняет прежний предел строгого парсера строки')
    старый.поля(ресурс['рождения'], {'координатор', 'владелец'})
    for роль in ('координатор', 'владелец'):
        рождение = ресурс['рождения'][роль]
        старый.поля(рождение, {'задача', 'хэш_корня', 'коммит'})
        старый.сумма(рождение['хэш_корня'], 64)
        старый.сумма(рождение['коммит'], 40)
        старый.требовать(рождение['задача'] == вход[роль]
            and старый.хэш(вход['корни'][роль].encode()) == рождение['хэш_корня'],
            'ресурс выбрал другое рождение или физический W')
    бюджет = Бюджет(ресурс['пределы'], начало)
    _контроль(корень, ресурс['контроль'], бюджет)
    _гит_под_сроком(корень, ('merge-base', '--is-ancestor',
        ресурс['контроль']['коммит'], выбранный['коммит']), бюджет)
    return ресурс, данные, бюджет


def _рождение(запись, источник, корень, ожидаемое):
    старый.требовать(запись['type'] == 'session_meta' and запись['ordinal'] == 0,
        'источник не начинается с отдельного рождения')
    содержимое = запись['payload']
    общие = {'base_instructions', 'cli_version', 'context_window', 'cwd', 'git',
        'history_mode', 'id', 'model_provider', 'originator', 'session_id', 'source',
        'thread_source', 'timestamp'}
    новые = {'creator_account_id', 'creator_user_id', 'runtime_workspace_roots'}
    старый.требовать(set(содержимое) in (общие, общие | новые)
        and (источник['роль'] != 'владелец' or set(содержимое) == общие | новые),
        'неизвестная оболочка рождения')
    старый.требовать(содержимое['id'] == содержимое['session_id'] == источник['задача'],
        'чужой UUID рождения')
    for ключ in ('cli_version', 'history_mode', 'model_provider', 'originator',
            'source', 'thread_source', 'timestamp'):
        старый.требовать(type(содержимое[ключ]) is str and содержимое[ключ],
            'неверное поле рождения')
    старый.временная_метка_UTC(содержимое['timestamp'])
    старый.абсолютное_имя(содержимое['cwd'])
    if 'runtime_workspace_roots' in содержимое:
        корни = содержимое['runtime_workspace_roots']
        старый.требовать(type(корни) is list and корни, 'нет рабочих корней рождения')
        for рабочий in корни:
            старый.абсолютное_имя(рабочий)
        старый.требовать(str(корень) in корни, 'чужой объявленный W рождения')
        for ключ in ('creator_account_id', 'creator_user_id'):
            старый.требовать(type(содержимое[ключ]) is str and содержимое[ключ],
                'неверные создатели рождения')
    старый.поля(содержимое['context_window'], {'window_id'})
    старый.идентификатор(содержимое['context_window']['window_id'])
    старый.поля(содержимое['base_instructions'], {'text', 'provenance'})
    старый.требовать(type(содержимое['base_instructions']['text']) is str
        and type(содержимое['base_instructions']['provenance']) is dict,
        'неверный материал инструкций рождения')
    старый.требовать(type(содержимое['git']) is dict and set(содержимое['git']) in
        ({'commit_hash', 'repository_url'}, {'commit_hash', 'branch', 'repository_url'}),
        'неизвестная Git-оболочка рождения')
    if 'branch' in содержимое['git']:
        старый.требовать(type(содержимое['git']['branch']) is str, 'неверная ветка рождения')
    старый.требовать(содержимое['git']['commit_hash'] == ожидаемое['коммит']
        and содержимое['git']['repository_url'] == 'https://github.com/fum-lab/fum.git'
        and содержимое['cwd'] == str(корень), 'чужие C, репозиторий или W рождения')
    if источник['роль'] == 'владелец':
        старый.требовать(содержимое['thread_source'] == 'agent_created_thread',
            'неизвестное происхождение владельца')


def _идентичность(состояние, граница):
    старый.требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_uid == os.getuid()
        and состояние.st_nlink == 1 and not состояние.st_mode & 0o022
        and состояние.st_size >= граница, 'неверные тип, владелец, ссылки, режим или размер RAW')
    return (состояние.st_dev, состояние.st_ino, состояние.st_mode,
        состояние.st_uid, состояние.st_gid, состояние.st_nlink)


def _сохранность(путь, дескриптор, исходная, граница):
    старый.требовать(старый.физический(str(путь)) == путь
        and _идентичность(os.fstat(дескриптор), граница)
        == _идентичность(путь.lstat(), граница) == исходная,
        'физический источник заменён или усечён')


def _читать(источник, вход, ресурс, бюджет, профиль):
    старый.поля(источник, {'роль', 'задача', 'путь', 'начало', 'конец', 'промежуточные'})
    роль = источник['роль']
    старый.требовать(роль in ('координатор', 'владелец')
        and источник['задача'] == вход[роль], 'чужая роль или UUID источника')
    for ключ in ('начало', 'конец'):
        старый.граница_нативного_источника(источник[ключ])
    конец = источник['конец']['граница']
    старый.требовать(источник['начало']['граница'] <= конец
        <= бюджет.пределы['сырых_байтов_на_источник'], 'превышен RAW-бюджет источника')
    префиксы = источник['промежуточные']
    старый.требовать(type(префиксы) is list
        and len(префиксы) <= бюджет.пределы['промежуточных_границ'],
        'превышен бюджет промежуточных границ')
    for префикс in префиксы:
        старый.граница_нативного_источника(префикс)
        старый.требовать(префикс['граница'] <= конец, 'промежуточный префикс после среза')
    старый.требовать(len({п['граница'] for п in префиксы}) == len(префиксы),
        'повтор промежуточной границы')
    путь = старый.физический(источник['путь'])
    исходная = _идентичность(путь.lstat(), конец)
    реестр = РеестрПолнойИстории(источник['задача'], вход['координатор'], вход['владелец'],
        [источник['начало'], источник['конец'], *префиксы], бюджет)
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        _сохранность(путь, дескриптор, исходная, конец)
        сырой = hashlib.sha256()
        строк = 0
        порядок = 0
        срез_рождения = ресурс['рождения'][роль]
        with os.fdopen(os.dup(дескриптор), 'rb') as поток:
            while поток.tell() < конец:
                бюджет.срок()
                начало = поток.tell()
                данные = поток.readline(min(бюджет.пределы['байтов_строки'] + 1, конец - начало))
                бюджет.чтение(len(данные))
                старый.требовать(0 < len(данные) <= бюджет.пределы['байтов_строки'],
                    'превышен бюджет строки либо источник усечён')
                отметка = time.perf_counter_ns()
                запись = старый.нативная_строка(данные)
                профиль['разбор_нс'] += time.perf_counter_ns() - отметка
                сырой.update(данные)
                позиция = поток.tell()
                реестр._сверить_префикс(начало, позиция, сырой)
                отметка = time.perf_counter_ns()
                if строк == 0:
                    _рождение(запись, источник, Path(вход['корни'][роль]), срез_рождения)
                    старый.требовать(позиция <= источник['начало']['граница'],
                        'начальная граница внутри рождения')
                else:
                    старый.требовать(запись['type'] != 'session_meta'
                        and запись['ordinal'] > порядок, 'повторное рождение или обратный ordinal')
                    реестр._учесть_строку(данные, запись,
                        {'начало': начало, 'конец': позиция, 'sha256': старый.хэш(данные)})
                профиль['учёт_нс'] += time.perf_counter_ns() - отметка
                порядок = запись['ordinal']
                строк += 1
            старый.требовать(поток.tell() == конец
                and сырой.hexdigest() == источник['конец']['sha256'], 'RAW разобранного среза расходится')
        _сохранность(путь, дескриптор, исходная, конец)
        return {'источник': источник, 'реестр': реестр, 'строк': строк,
            'путь': путь, 'идентичность': исходная}
    except BaseException:
        реестр.ошибка = реестр.копии.ошибка = True
        raise
    finally:
        os.close(дескриптор)


def _пересверить(чтение, бюджет):
    источник = чтение['источник']
    путь = чтение['путь']
    конец = источник['конец']['граница']
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        _сохранность(путь, дескриптор, чтение['идентичность'], конец)
        хэш = hashlib.sha256()
        позиция = 0
        границы = {п['граница']: п['sha256'] for п in
            [источник['начало'], источник['конец'], *источник['промежуточные']]}
        for граница in sorted(границы):
            while позиция < граница:
                бюджет.срок()
                блок = os.pread(дескриптор, min(1 << 20, граница - позиция), позиция)
                старый.требовать(bool(блок), 'RAW усечён при заключительной сверке')
                бюджет.чтение(len(блок))
                хэш.update(блок)
                позиция += len(блок)
            старый.требовать(хэш.hexdigest() == границы[граница],
                'RAW изменился после полного учёта обоих потоков')
        _сохранность(путь, дескриптор, чтение['идентичность'], конец)
        состояние = os.fstat(дескриптор)
        чтение['последние_метаданные'] = (состояние.st_size,
            состояние.st_mtime_ns, состояние.st_ctime_ns)
        return состояние.st_size - конец
    finally:
        os.close(дескриптор)


def сериализовать_ограниченно(значение, предел, срок):
    данные = bytearray()
    кодировщик = json.JSONEncoder(ensure_ascii=False, sort_keys=True,
        separators=(',', ':'), allow_nan=False)
    for часть in кодировщик.iterencode(значение):
        срок()
        старый.требовать(len(часть) <= предел - len(данные) - 1,
            'превышен конечный бюджет результата')
        кусок = часть.encode('utf-8')
        старый.требовать(len(кусок) <= предел - len(данные) - 1,
            'превышен конечный бюджет результата')
        данные.extend(кусок)
    данные.extend(b'\n')
    срок()
    return bytes(данные)


def прочитать_с_байтами(корень, вход, выбранный_ресурс):
    """Независимый selector является отдельным аргументом; состояния извне нет."""
    начало = time.perf_counter_ns()
    срок_выбора = Бюджет({'время_нс': ПРЕДЕЛ_ВЫБОРА_НС}, начало)
    вход = старый.разобрать_JSON(сериализовать_ограниченно(вход,
        ПРЕДЕЛ_ДОКУМЕНТА, срок_выбора.срок), ПРЕДЕЛ_ДОКУМЕНТА)
    выбранный_ресурс = старый.разобрать_JSON(сериализовать_ограниченно(выбранный_ресурс,
        ПРЕДЕЛ_ДОКУМЕНТА, срок_выбора.срок), ПРЕДЕЛ_ДОКУМЕНТА)
    профиль = {'подготовка_нс': 0, 'разбор_нс': 0, 'учёт_нс': 0, 'повторное_чтение_нс': 0}
    корень = старый.физический(str(корень), каталог=True)
    старый.поля(вход, {'схема', 'координатор', 'владелец', 'контроль', 'корни', 'источники'})
    старый.требовать(вход['схема'] == СХЕМА_ВХОДА, 'неверная версия нового читающего входа')
    for роль in ('координатор', 'владелец'):
        старый.идентификатор(вход[роль])
    старый.требовать(вход['координатор'] != вход['владелец'], 'ROOT и владелец совпали')
    старый.поля(вход['корни'], {'координатор', 'владелец'})
    for рабочий in вход['корни'].values():
        старый.физический(рабочий, каталог=True)
    ресурс, сырые_ресурсы, бюджет = _ресурс(корень, вход, выбранный_ресурс, начало)
    бюджет.срок()
    источники = вход['источники']
    старый.требовать(type(источники) is list and len(источники) == 2
        and [э['роль'] for э in источники] == ['координатор', 'владелец']
        and источники[0]['путь'] != источники[1]['путь'], 'нужны два разных упорядоченных источника')
    профиль['подготовка_нс'] = time.perf_counter_ns() - начало
    чтения = []
    try:
        for источник in источники:
            чтения.append(_читать(источник, вход, ресурс, бюджет, профиль))
        отметка = time.perf_counter_ns()
        хвосты = [_пересверить(чтение, бюджет) for чтение in чтения]
        _контроль(корень, ресурс['контроль'], бюджет)
        старый.требовать(_прочитать_выбор(корень, выбранный_ресурс, бюджет) == сырые_ресурсы,
            'ресурсный документ изменился')
        профиль['повторное_чтение_нс'] = time.perf_counter_ns() - отметка
        результаты = []
        for чтение, хвост in zip(чтения, хвосты, strict=True):
            бюджет.срок()
            учёт = чтение['реестр'].завершить()
            результаты.append({'источник': чтение['источник'], 'строк': чтение['строк'],
                'реестр': учёт, 'непроверенный_хвост': хвост,
                'сырые_байты_выбранного_префикса_сохранены': True})
        бюджет.срок()
        результат = {'схема': СХЕМА_ВЫХОДА, 'ресурс': выбранный_ресурс,
            'координатор': вход['координатор'], 'владелец': вход['владелец'],
            'контроль': вход['контроль'], 'источники': результаты,
            'профиль': dict(профиль, прочитано_байтов=бюджет.прочитано),
            'полнота_выбранных_префиксов_доказана': True,
            'полнота_истории_доказана': False, 'полный_LIVE_хвост_доказан': False,
            'разрешение_эффекта': False}
        отметка = time.perf_counter_ns()
        данные = сериализовать_ограниченно(результат,
            ресурс['пределы']['байтов_результата'], бюджет.срок)
        сериализация = time.perf_counter_ns() - отметка
        _контроль(корень, ресурс['контроль'], бюджет)
        for чтение in чтения:
            состояние = чтение['путь'].lstat()
            старый.требовать(старый.физический(str(чтение['путь'])) == чтение['путь']
                and _идентичность(состояние, чтение['источник']['конец']['граница'])
                == чтение['идентичность'] and (состояние.st_size,
                    состояние.st_mtime_ns, состояние.st_ctime_ns) == чтение['последние_метаданные'],
                'RAW изменился после заключительной сверки')
        бюджет.срок()
        return результат, данные, {'сериализация_нс': сериализация,
            'общая_нс': time.perf_counter_ns() - начало}
    except BaseException:
        for чтение in чтения:
            чтение['реестр'].ошибка = чтение['реестр'].копии.ошибка = True
        raise


def прочитать(корень, вход, выбранный_ресурс):
    return прочитать_с_байтами(корень, вход, выбранный_ресурс)[0]


def _вход_джейсон(имя):
    путь = старый.физический(имя)
    до = путь.lstat()
    исходная = _идентичность(до, 1)
    старый.требовать(до.st_size <= ПРЕДЕЛ_ДОКУМЕНТА, 'превышен размер CLI-входа')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        _сохранность(путь, дескриптор, исходная, 1)
        данные = bytearray()
        while len(данные) < до.st_size:
            блок = os.read(дескриптор, min(65536, до.st_size - len(данные)))
            старый.требовать(bool(блок), 'CLI-вход усечён')
            данные.extend(блок)
        _сохранность(путь, дескриптор, исходная, 1)
        старый.требовать(os.fstat(дескриптор).st_size == до.st_size
            and os.pread(дескриптор, до.st_size, 0) == данные, 'CLI-вход изменён')
        return старый.разобрать_JSON(bytes(данные), ПРЕДЕЛ_ДОКУМЕНТА)
    finally:
        os.close(дескриптор)


def главная():
    разбор = argparse.ArgumentParser(allow_abbrev=False, description=__doc__)
    разбор.add_argument('--корень-репозитория', required=True)
    разбор.add_argument('--вход', required=True)
    разбор.add_argument('--выбранный-ресурс', required=True)
    аргументы = разбор.parse_args()
    try:
        _, данные, _ = прочитать_с_байтами(аргументы.корень_репозитория,
            _вход_джейсон(аргументы.вход), _вход_джейсон(аргументы.выбранный_ресурс))
        sys.stdout.buffer.write(данные)
        return 0
    except (ValueError, OSError, KeyError, TypeError, UnicodeError, RecursionError) as ошибка:
        sys.stderr.buffer.write(старый.байты({'схема': 'fum.отказ-полного-читающего-реестра.1',
            'ошибка': str(ошибка), 'разрешение_эффекта': False}))
        return 2


if __name__ == '__main__':
    raise SystemExit(главная())

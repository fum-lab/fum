    отслеживаемые = поручения._гит(корень, '--literal-pathspecs', 'ls-files', '-z', '--', *цели).split('\0')
    требовать(all(not имя or os.path.lexists(корень / имя) for имя in отслеживаемые), 'удаление цели требует отдельной подготовки')
    профиль = нап.get('профиль'); стадии = профиль.get('стадии') if type(профиль) is dict else None
    требовать(type(стадии) is list and len(стадии) >= 2, 'нужны хотя бы две стадии профиля ROOT')
    имена = []
    for стадия in стадии:
        имя = стадия['имя']; значение = стадия['длительность_нс']
        требовать(type(имя) is str and имя.strip() and имя not in имена, 'неразличимые стадии профиля')
        требовать((type(значение) is int and значение >= 0) or (значение is None
            and type(стадия.get('основание')) is str and стадия['основание'].strip()), 'нужны наблюдение либо null с причиной')
        имена.append(имя)

def резервировать_результат(назначение):
    """Файл является сохраняемым consume marker также при неизвестном исходе."""
    файл = приватный(назначение, существует=False)
    требовать(not os.path.lexists(файл), 'занят полный результат; повтор эффекта запрещён')
    with os.fdopen(os.open(файл, os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW, 0o600), 'wb') as поток:
        состояние = os.fstat(поток.fileno())
        поток.write(байты({'схема':'fum.полный-результат-подготовки.1', 'состояние':'начато'}))
        поток.flush(); os.fsync(поток.fileno())
    return файл, (состояние.st_dev, состояние.st_ino)


def сохранить_результат(резерв, результат):
    файл, идентичность = резерв
    состояние = файл.lstat()
    требовать(stat.S_ISREG(состояние.st_mode) and (состояние.st_dev, состояние.st_ino) == идентичность,
        'подменён зарезервированный полный результат')
    временный = файл.with_name(файл.name+'.'+uuid.uuid4().hex+'.tmp')
    try:
        with os.fdopen(os.open(временный, os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW, 0o600), 'wb') as поток:
            поток.write(байты(результат)); поток.flush(); os.fsync(поток.fileno())
        os.replace(временный, файл)
    finally:
        if os.path.lexists(временный): временный.unlink()


def измерить_фазу(имя, функция, интервалы=None):
    """Профильный callback получает интервал после завершения таймера."""
    if интервалы is None: return функция()
    начало=time.perf_counter_ns()
    try: return функция()
    finally:
        конец=time.perf_counter_ns()
        интервалы({'фаза':имя,'наносекунды':конец-начало})


def наблюдать_выполнение(резерв, функция, наблюдатель=None, *, интервалы=None):
    события = []; маркер = _НАБЛЮДЕНИЕ.set((события, наблюдатель))
    try:
        полный = функция()
    finally:
        _НАБЛЮДЕНИЕ.reset(маркер)
    измерить_фазу('сериализация-результат',lambda:сохранить_результат(резерв, полный),интервалы)
    код = полный['код']
    return {'код':код if type(код) is int else 1, 'события':события, 'коммит_создан':False}


def выполнить_с_наблюдением(вход, план, ожидаемый_sha256, *, полный_результат, наблюдатель=None):
    файл = приватный(полный_результат, существует=False)
    требовать(not os.path.lexists(файл), 'занят полный результат; повтор эффекта запрещён')
    требовать(хэш(байты(план)) == ожидаемый_sha256 and построить_план(вход) == план,
        'дрейф перед резервированием полного результата')
    п=прочитать(вход['вход_коммита'])
    роли={Path(э) for э in план['снимок']['файлы']}
    роли.update(Path(п[к]) for к in ('сообщение','подготовка','квитанция','кэш_модели','источник_модели'))
    роли.update(Path(и['путь']) for и in п['источники'])
    роли.update(Path(и['кэш']) for и in п['источники'] if 'кэш' in и)
    требовать(файл not in роли,'полный результат пересекает роль подготовки')
    резерв = резервировать_результат(файл)
    return наблюдать_выполнение(резерв, lambda: выполнить(вход, план, ожидаемый_sha256), наблюдатель)


def приватный(значение, *, существует=True, режим=0o600):
    файл = адреса.точный_абсолютный(значение, приватный=True)
    родитель = файл.parent
    требовать(родитель.is_dir(), 'отсутствует собственный private parent')
    состояние = родитель.stat()
    требовать(состояние.st_uid == os.getuid() and stat.S_IMODE(состояние.st_mode) == 0o700,
        'собственный private parent должен иметь режим0700')
    if os.path.lexists(файл):
        состояние = файл.lstat()
        требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_uid == os.getuid()
            and stat.S_IMODE(состояние.st_mode) == режим, 'неверное владение или private mode')
    else:
        требовать(not существует, 'отсутствует приватный вход')
    return файл



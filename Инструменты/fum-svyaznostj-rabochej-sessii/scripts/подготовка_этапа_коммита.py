def исполнить_команду(аргументы, корень):
    начало = time.perf_counter_ns()
    процесс = subprocess.run(аргументы, cwd=корень, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        env={**os.environ, 'PYTHONDONTWRITEBYTECODE': '1', 'GIT_OPTIONAL_LOCKS': '0'}, shell=False)
    каналы = {имя: {'байтов': len(сырые), 'sha256': хэш(сырые),
        'base64': base64.b64encode(сырые).decode('ascii')}
        for имя, сырые in [('stdout', процесс.stdout), ('stderr', процесс.stderr)]}
    return {'аргументы': аргументы, 'код': процесс.returncode,
        'stdout': процесс.stdout.decode('utf-8', errors='replace'),
        'stderr': процесс.stderr.decode('utf-8', errors='replace'), 'каналы': каналы,
        'длительность_наносекунды': time.perf_counter_ns() - начало}



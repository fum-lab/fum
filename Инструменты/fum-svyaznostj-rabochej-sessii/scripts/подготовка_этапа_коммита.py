def снимок(корень, параметры, вход, дополнительные):
    имена = [корень / элемент for элемент in параметры['разрешённые_цели']]
    имена += [Path(вход[элемент]) for элемент in ('вход_коммита', 'поручение', 'наполнение', 'план_наполнения')]
    имена += дополнительные
    файлы = {}
    for файл in sorted(set(имена)):
        if os.path.lexists(файл):
            состояние = файл.lstat()
            требовать(stat.S_ISREG(состояние.st_mode), 'необычный файл снимка')
            файлы[str(файл)] = {'sha256': хэш(файл.read_bytes()), 'режим': stat.S_IMODE(состояние.st_mode)}
        else:
            файлы[str(файл)] = None
    индекс = Path(поручения._гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index'))
    return {'HEAD': поручения._гит(корень, 'rev-parse', 'HEAD'),
        'ref': поручения._гит(корень, 'symbolic-ref', 'HEAD'),
        'индекс_sha256': хэш(индекс.read_bytes()), 'файлы': файлы}



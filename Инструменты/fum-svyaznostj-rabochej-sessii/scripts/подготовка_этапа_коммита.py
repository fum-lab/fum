def обновить_свежесть(корень, цели, время):
    """Штатный полный check, whitelist и повторная стабильность перед apply."""
    def граница():
        индекс = Path(поручения._гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index'))
        return {'Markdown': {п.relative_to(корень).as_posix(): (stat.S_IMODE(п.stat().st_mode), хэш(п.read_bytes()))
            for п in свежесть.find_markdown_paths(корень)}, 'индекс': хэш(индекс.read_bytes()),
            'HEAD': поручения._гит(корень, 'rev-parse', 'HEAD'), 'ref': поручения._гит(корень, 'symbolic-ref', 'HEAD')}
    до = граница()
    проверка = свежесть.update_repository(корень, now=время, check=True)
    изменяемые = [п.relative_to(корень).as_posix() for п in проверка.changed_paths]
    требовать(set(изменяемые) <= set(цели), 'recency вне ACT: ' + ', '.join(sorted(set(изменяемые) - set(цели))))
    разрешённые_ошибки = {префикс + имя for имя in изменяемые
        for префикс in ('missing recency metadata: ', 'stale recency metadata: ', 'stale recency index: ')}
    требовать(set(проверка.errors) <= разрешённые_ошибки, 'структурный отказ recency: ' + '; '.join(проверка.errors))
    требовать(до == граница(), 'дрейф во время recency check')
    повтор = свежесть.update_repository(корень, now=время, check=True)
    требовать(повтор == проверка and до == граница(), 'дрейф перед recency apply')
    итог = свежесть.update_repository(корень, now=время, check=False)
    требовать(not итог.errors, 'исходный отказ применения recency: ' + '; '.join(итог.errors))
    требовать([п.relative_to(корень).as_posix() for п in итог.changed_paths] == изменяемые,
        'recency применил другой состав; законные предыдущие эффекты сохранены')
    return {'изменённые_пути': изменяемые}



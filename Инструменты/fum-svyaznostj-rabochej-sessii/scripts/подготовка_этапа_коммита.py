    требовать(set(изменённые) <= set(п['разрешённые_цели']), 'dirty путь вне разрешения ROOT')
    начало = вход['начало']
    требовать(type(начало) is dict and set(начало) == {'метка', 'заголовок'}, 'неверные поля start')
    требовать(начало['заголовок'] == п['заголовок'], 'разные заголовки start и коммита')
    запрос = корень / п['запрос']; каталог_этапа = запрос.parent
    требовать(п['запрос'] == f'Журнал/{каталог_этапа.name}/запрос.md',
        'неканоничный ROOT этап')
    требовать(открытый or not os.path.lexists(каталог_этапа),
        'новый ROOT этап уже существует или неканоничен')
    модель = корень / п['история_модели']
    требовать(модель == каталог_этапа / 'материалы/история-модели.json', 'неверный адрес новой модели')
    прежние = []
    if открытый:
        требовать(not os.path.lexists(_маркер_первой_подготовки(п)),
            'занят эпизод первой подготовки; повтор эффекта запрещён')

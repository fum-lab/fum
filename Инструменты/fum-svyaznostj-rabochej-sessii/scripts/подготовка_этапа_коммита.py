        требовать(set(проверка) == {'идентификатор', 'порядок', 'название', 'класс', 'аргументы'}, 'неверные поля ROOT проверки')
        требовать(проверка['класс'] in {'адресная', 'полная'}, 'ROOT выбирает адресный либо полный контур')

def корневые_команды(параметры):
    """Выбор штатным читателем до появления карточки; время из точных raw span."""
    import назначение_текущего_этапа as этап
    if этап.активен():
        return этап.команды(параметры)
    результат = []
    времена = []
    позиции = {}; прежний_источник = None
    требовать(type(параметры['источники']) is list and параметры['источники'], 'нужны источники ROOT')
    for источник in параметры['источники']:
        поля = {'путь', 'задача', 'экземпляры', 'граница_снимка'}
        требовать(set(источник) in (поля, поля | {'кэш'}), 'неверные поля источника ROOT')
        сним = коммит.сообщения.прочитать_сообщения(источник['путь'], источник['задача'],
            корень_репозитория=параметры['корень'], кэш=источник.get('кэш'), без_записи=True)
        коммит.выбор_команд.проверить_снимок(сним, источник['граница_снимка'], требовать)
        номера = источник['экземпляры']
        требовать(type(номера) is list and номера and len(номера) == len(set(номера)), 'повторный ID команды')
        выбор = [э for э in сним['сообщения'] if э['экземпляр'] in номера]
        требовать([э['экземпляр'] for э in выбор] == номера, 'нарушен порядок ID или отсутствует команда')
        with Path(источник['путь']).open('rb') as поток:
            for э in выбор:
                содержимое = э['содержимое']
                требовать(э['происхождение'] == 'человек' and len(содержимое) == 1
                    and содержимое[0]['type'] == 'input_text' and type(содержимое[0]['text']) is str
                    and содержимое[0]['text'], 'неподдержанный первичный ввод ROOT')
                позиция = э['позиция']; поток.seek(позиция['начало'])
                сырые = поток.read(позиция['конец'] - позиция['начало'])
                требовать(хэш(сырые) == позиция['sha256'], 'подмена raw span команды')
                метка = json.loads(сырые).get('timestamp')
                требовать(type(метка) is str, 'неизвестна хронология выбранных источников')
                время = datetime.fromisoformat(метка.replace('Z', '+00:00'))
                требовать(время.tzinfo is not None, 'неизвестная временная зона команды')
                ключ = (источник['задача'], сним['источник'])
                требовать(позиция['начало'] >= позиции.get(ключ, -1), 'нарушен глобальный порядок raw positions')
                требовать(not времена or время != времена[-1] or ключ == прежний_источник,
                    'равное время разных источников не доказывает хронологию')
                позиции[ключ] = позиция['конец']; прежний_источник = ключ
                времена.append(время)
                результат.append({'задача': источник['задача'], 'экземпляр': э['экземпляр'],
                    'позиция': позиция, 'текст': содержимое[0]['text']})
    ключи = [(э['задача'], э['экземпляр']) for э in результат]
    требовать(len(ключи) == len(set(ключи)), 'ID повторён между источниками')
    требовать(времена == sorted(времена), 'нарушена хронология источников ROOT')
    return результат


def проверить_корневой_контур(параметры, корень, обычный):
    """Дополнительная граница фасада; общий создатель .5 не меняется."""
    if обычный:
        требовать(параметры['родители'] == [параметры['исходный_коммит']],
            'обычный ROOT требует единственного родителя исходного HEAD')
        каталог = Path(поручения._гит(корень, 'rev-parse', '--absolute-git-dir'))
        требовать(not os.path.lexists(каталог / 'MERGE_HEAD'), 'обычный ROOT запрещает любой MERGE_HEAD')
    коммит.адрес(параметры)
    if not обычный:
        требовать(len(параметры['родители']) == 2, 'dirty_start_before_merge: сначала merge владельца')
    требовать(not коммит.гит(корень, 'ls-files', '--unmerged', '-z'), 'неразрешённый индекс ROOT')


def корневой_план(вход, *, выбранный_состав=None):
    """Точная область нового ROOT .5; обычный контур выбирается явно."""
    независимый = _контекст_независимого_фасада(вход, выбранный_состав)
    требовать(независимый is None or not независимый['дочерний'],
        'ROOT фасад не принимает child .10')
    открытый = независимый is not None and независимый['открытый']
    поля = {'вход_коммита', 'наполнение', 'план_наполнения', 'время',
        'повтор', 'начало', 'проверки', 'связность', 'готовность'}
    if независимый is None:
        требовать(type(вход) is dict and поля <= set(вход)
            and set(вход)-поля <= {'контур', 'обновления', 'перенос_модели'}, 'неверные поля ROOT фасада')
    обычный = 'контур' in вход
    требовать(not обычный or вход['контур'] == 'обычный', 'неизвестный ROOT контур')
    требовать('перенос_модели' not in вход or обычный, 'перенос модели требует обычный ROOT контур')
    требовать(вход['повтор'] is False, 'ROOT start требует новый этап; повтор карточки не подразумевается')
    время = свежесть.parse_display_time(вход['время'])
    требовать(свежесть.format_msk(время) == вход['время'], 'нужно точное время recency')
    п = прочитать(вход['вход_коммита'])
    if независимый is None:
        требовать(set(п) == коммит.ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ and п['схема'] == 'fum.создание-коммита.5'
            and п['режим'] == 'контрольная-точка', 'ROOT принимает прежнюю .5 без полей ordinary ACT')

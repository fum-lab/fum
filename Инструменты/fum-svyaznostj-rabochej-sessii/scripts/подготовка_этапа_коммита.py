def приватный(значение, *, существует=True, режим=0o600):
    файл = адреса.точный_абсолютный(значение, приватный=True)
    родитель = файл.parent
    требовать(родитель.is_dir(), 'отсутствует собственный private parent')
    состояние = родитель.stat()
    требовать(состояние.st_uid == os.getuid() and stat.S_IMODE(состояние.st_mode) == 0o700,
        'собственный private parent должен иметь режим0700')
    if os.path.lexists(файл):
        состояние = файл.lstat()
        требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_uid == os.getuid()
            and stat.S_IMODE(состояние.st_mode) == режим, 'неверное владение или private mode')
    else:
        требовать(not существует, 'отсутствует приватный вход')
    return файл



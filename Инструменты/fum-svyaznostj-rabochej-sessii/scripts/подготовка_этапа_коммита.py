def снимок(корень, параметры, вход, дополнительные):
    имена = [корень / элемент for элемент in параметры['разрешённые_цели']]
    имена += [Path(вход[элемент]) for элемент in ('вход_коммита', 'поручение', 'наполнение', 'план_наполнения')]
    имена += дополнительные
    файлы = {}
    for файл in sorted(set(имена)):
        if os.path.lexists(файл):
            состояние = файл.lstat()
            требовать(stat.S_ISREG(состояние.st_mode), 'необычный файл снимка')
            файлы[str(файл)] = {'sha256': хэш(файл.read_bytes()), 'режим': stat.S_IMODE(состояние.st_mode)}
        else:
            файлы[str(файл)] = None
    индекс = Path(поручения._гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index'))
    return {'HEAD': поручения._гит(корень, 'rev-parse', 'HEAD'),
        'ref': поручения._гит(корень, 'symbolic-ref', 'HEAD'),
        'индекс_sha256': хэш(индекс.read_bytes()), 'файлы': файлы}


def питон(сценарий, *хвост):
    return [sys.executable, '-B', str(сценарий), *map(str, хвост)]


def снимок_обновления(корень, имя):
    if имя == 'журнал':
        имена = {п.as_posix() for п in каркас._canonical_requests(корень).values()}
        имена |= {п.relative_to(корень).as_posix() for п in (корень/'Журнал').glob('*/отчёт.md') if п.is_file()}
        имена.add('Журнал/README.md')
    else:
        требовать(имя == 'recency', 'неизвестное обновление')
        имена = {п.relative_to(корень).as_posix() for п in свежесть.find_markdown_paths(корень)}
    результат = {}
    кэш_каталогов = {}
    for имя_пути in sorted(имена):
        путь = коммит.охват.точный_путь(корень, имя_пути, кэш_каталогов)
        if os.path.lexists(путь):
            с = путь.lstat(); требовать(stat.S_ISREG(с.st_mode), 'необычная зависимость обновления')
            результат[имя_пути] = {'sha256':хэш(путь.read_bytes()), 'режим':stat.S_IMODE(с.st_mode)}
        else: результат[имя_пути] = None
    return результат


def план_обновлений(вход, корень, цели, время):
    имена = вход.get('обновления', [])
    требовать(type(имена) is list and all(type(и) is str and и in {'журнал','recency'} for и in имена)
        and len(set(имена)) == len(имена), 'неизвестное или повторное обновление')
    результат = {}
    for имя in ('журнал','recency'):
        if имя not in имена: continue
        выход = 'Журнал/README.md' if имя=='журнал' else свежесть.INDEX_PATH.as_posix()
        требовать(выход in цели, 'индекс обновления вне разрешения')
        входы = снимок_обновления(корень, имя)
        выходы = [выход] if имя=='журнал' else sorted({ц for ц in цели if ц.endswith('.md')}|{выход})
        for ц in выходы:
            if ц not in входы:
                ф=коммит.охват.точный_путь(корень,ц)
                if os.path.lexists(ф):
                    с=ф.lstat(); требовать(stat.S_ISREG(с.st_mode),'необычный выход обновления')
                    входы[ц]={'sha256':хэш(ф.read_bytes()),'режим':stat.S_IMODE(с.st_mode)}
                else: входы[ц]=None
        if имя == 'журнал':
            требовать(входы[выход] is not None, 'отсутствует индекс Журнала')
            аргументы = питон(ИНСТРУМЕНТЫ/'fum-struktura-papok-zaprosov/scripts/struktura-papok-zaprosov.py','reindex','--repo-root',корень)
        else:
            основа = питон(Path(свежесть.__file__),'--repo-root',корень,'--now',время.isoformat())
            аргументы = {'проверка':[*основа,'--check'], 'применение':основа}
        результат[имя] = {'входы':входы, 'исходные_выходы':{ц:входы[ц] for ц in выходы},
            'конечные_выходы':выходы, 'аргументы':аргументы,
            'граница':'Конечный перечень допустимых выходов; точный изменённый состав и SHA даёт исполнение.'}
    return результат


def проверить_назначение_курсора(параметры, корень):
    файл = приватный(параметры['кэш_модели'],существует=False)
    if os.path.lexists(файл):
        оболочка = прочитать(файл)
        требовать(type(оболочка) is dict and set(оболочка)=={'данные','sha256'}
            and хэш(коммит.сообщения._байты(оболочка['данные']))==оболочка['sha256'], 'повреждённый модельный курсор')
        прежний = оболочка['данные']
        требовать(type(прежний) is dict and прежний.get('назначение')==str(корень/параметры['история_модели']),
            'чужой модельный курсор; штатный перенос выполняется отдельно')


def проверить_обновление(корень, имя, сведения, цели):
    текущие = снимок_обновления(корень, имя)
    for путь in set(сведения['входы']) | set(текущие):
        if путь not in цели:
            требовать(сведения['входы'].get(путь)==текущие.get(путь), 'дрейф транзитивной зависимости: '+путь)
    return текущие


def обновить_журнал(корень, цели, сведения):
    до = проверить_обновление(корень,'журнал',сведения,цели)
    имена, отчёты, метки = каркас._future_sessions(корень, ())
    файл = корень/'Журнал/README.md'; режим = stat.S_IMODE(файл.stat().st_mode)
    ожидаемые = каркас._index_text(каркас._read_text(файл),имена,отчёты,метки,корень,preferred={}).encode()
    требовать(до==снимок_обновления(корень,'журнал'), 'дрейф перед refresh Журнала')
    итог = каркас.reindex_journal(корень,None)
    требовать(файл.read_bytes()==ожидаемые and stat.S_IMODE(файл.stat().st_mode)==режим, 'refresh изменил иные байты/режим')
    после = снимок_обновления(корень,'журнал')
    требовать({п:с for п,с in после.items() if п!='Журнал/README.md'}
        == {п:с for п,с in до.items() if п!='Журнал/README.md'}, 'refresh изменил чужой вход')
    return {'результат':итог, 'аргументы':сведения['аргументы'], 'входы':до,
        'ожидаемый_sha256':хэш(ожидаемые), 'выходы':{'Журнал/README.md':после['Журнал/README.md']}}


def обновить_объявленную_свежесть(корень, цели, время, сведения):
    до = проверить_обновление(корень,'recency',сведения,цели)
    итог = обновить_свежесть(корень,цели,время)
    после = снимок_обновления(корень,'recency')
    изменённые = set(итог['изменённые_пути'])
    требовать(изменённые == {п for п in set(до)|set(после) if до.get(п)!=после.get(п)},
        'recency изменил другой состав входов')
    требовать(all(до.get(п) is None or (после.get(п) is not None
        and до[п]['режим']==после[п]['режим']) for п in изменённые), 'recency изменил режим')
    return {**итог,'аргументы':сведения['аргументы'],'входы':до,
        'выходы':{п:после[п] for п in sorted(изменённые)}}


def построить_план(вход):
    """Читает привязку и конечные пути; не вызывает процессы с эффектами."""
    if type(вход) is dict and 'начало' in вход:
        return корневой_план(вход)
    поля = {'вход_коммита', 'поручение', 'наполнение','план_наполнения', 'время', 'повтор', 'проверки', 'связность'}
    требовать(type(вход) is dict and set(вход) in (поля, поля|{'обновления'}), 'неверные поля входа фасада')
    требовать(type(вход['повтор']) is bool, 'повтор должен быть bool')
    время = свежесть.parse_display_time(вход['время'])
    требовать(свежесть.format_msk(время) == вход['время'], 'нужно точное время recency')
    параметры = прочитать(вход['вход_коммита'])
    выбор = прочитать(вход['поручение'])
    поручения.проверить(параметры, выбор, новый_эффект=True)
    корень = адреса.проверить_пути(параметры)
    проверить_назначение_курсора(параметры,корень)
    for ключ in ('сообщение', 'подготовка', 'квитанция'):
        файл = приватный(параметры[ключ], существует=False)
        требовать(not os.path.lexists(файл), 'нужны новые выходы подготовки')
    приватный(параметры['кэш_модели'], существует=False)
    for источник in параметры['источники']:
        if 'кэш' in источник:
            приватный(источник['кэш'], существует=False)

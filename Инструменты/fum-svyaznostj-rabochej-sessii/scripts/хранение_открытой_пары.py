"""Точный rename начальной пары; полномочия и Git закрепляет вызывающий ROOT.

Вызывающий сохраняет план и результат проверки до эффекта и держит один замок
на обе области. Успех не означает установку S.2 или разрешение коммита.
"""
import hashlib
import json
import os
from pathlib import Path
import stat


def требовать(условие, сообщение):
    if not условие:
        raise ValueError(сообщение)


def метка(мета, *, каталог=False):
    # rename меняет ctime каталога, чтение может менять atime.
    поля = (мета.st_dev, мета.st_ino, мета.st_mode, мета.st_uid, мета.st_gid)
    return list(поля if каталог else поля +
        (мета.st_nlink, мета.st_size, мета.st_mtime_ns, мета.st_ctime_ns))


def проверить(папка, план):
    папка = Path(папка)
    требовать(папка.is_absolute() and папка.resolve() == папка,
        'нужен физический путь пары')
    мета = папка.lstat()
    требовать(stat.S_ISDIR(мета.st_mode), 'пара не является каталогом')
    файлы = план['файлы']
    требовать(len(файлы) == 2 and {Path(ф['путь']).name for ф in файлы} ==
        {'запрос.md', 'отчёт.md'}, 'нужна точная начальная пара')
    имена = {п.name for п in папка.iterdir()}
    требовать(имена in ({'запрос.md', 'отчёт.md'},
        {'запрос.md', 'отчёт.md', 'материалы'}), 'лишние данные открытой пары')
    результат = {'каталог': метка(мета, каталог=True), 'файлы': {}}
    for файл in файлы:
        имя = Path(файл['путь']).name
        путь = папка / имя
        до = путь.lstat()
        требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1
            and stat.S_IMODE(до.st_mode) == файл['режим'], 'неверный тип или режим пары')
        данные = путь.read_bytes()
        требовать(метка(путь.lstat()) == метка(до), 'дрейф файла при чтении')
        требовать(hashlib.sha256(данные).hexdigest() == файл['sha256'],
            'пара уже изменена после начального плана')
        результат['файлы'][имя] = метка(до)
    if 'материалы' in имена:
        путь = папка / 'материалы'
        мета = путь.lstat()
        требовать(stat.S_ISDIR(мета.st_mode) and not list(путь.iterdir()),
            'материалы должны быть пустым обычным каталогом')
        результат['материалы'] = метка(мета, каталог=True)
    return результат


def переместить(откуда, куда, план, ожидается):
    откуда, куда = Path(откуда), Path(куда)
    требовать(откуда != куда and all(p.is_absolute() and p.resolve() == p
        and p.parent.is_dir() for p in (откуда, куда)), 'неверные адреса перемещения')
    есть = [os.path.lexists(p) for p in (откуда, куда)]
    требовать(есть in ([True, False], [False, True]),
        'нужно ровно одно существующее расположение пары')
    текущий = откуда if есть[0] else куда
    требовать(проверить(текущий, план) == ожидается, 'изменилась идентичность пары')
    if есть[1]:
        return {'повтор': True}
    # Только один писатель под замком; EXDEV не превращается в copy/delete.
    os.rename(откуда, куда)
    for папка in {откуда.parent, куда.parent}:
        fd = os.open(папка, os.O_RDONLY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    требовать(not os.path.lexists(откуда) and проверить(куда, план) == ожидается,
        'перемещение не подтверждено')
    return {'повтор': False}


def _сохранить_квитанцию(путь, значение):
    данные = (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()
    fd = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, 'wb') as файл:
        файл.write(данные)
        файл.flush()
        os.fsync(файл.fileno())
    fd = os.open(путь.parent, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def вернуть_с_квитанцией(откуда, куда, план, ожидается, квитанция, основания):
    """Под тем же замком завершает возврат, включая прерывание до квитанции."""
    квитанция = Path(квитанция)
    требовать(квитанция.is_absolute() and квитанция.resolve() == квитанция,
        'нужен физический путь квитанции')
    требовать(isinstance(основания, dict) and 'результат' not in основания,
        'неверные основания возврата')
    прежняя = None
    if os.path.lexists(квитанция):
        мета = квитанция.lstat()
        требовать(stat.S_ISREG(мета.st_mode) and мета.st_nlink == 1,
            'неверный файл квитанции')
        прежняя = json.loads(квитанция.read_bytes())
        требовать(метка(квитанция.lstat()) == метка(мета), 'дрейф квитанции')
        требовать(isinstance(прежняя, dict) and
            прежняя.get('результат') in ({'повтор': True}, {'повтор': False}) and
            {k: v for k, v in прежняя.items() if k != 'результат'} == основания,
            'квитанция относится к другому возврату')
        требовать(not os.path.lexists(откуда) and os.path.lexists(куда),
            'квитанция противоречит расположению пары')
    результат = переместить(откуда, куда, план, ожидается)
    if прежняя is None:
        _сохранить_квитанцию(квитанция, {**основания, 'результат': результат})
    return результат

#!/usr/bin/env python3
"""Сохранить объявленную границу этапа и вычислить необходимость его фиксации."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import time

import готовность_этапа as готовность
import история_модели as хранение


def без_повторов(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ValueError("повторный ключ JSON: " + ключ)
        результат[ключ] = значение
    return результат


def прочитать(путь, приватный=False):
    return json.loads(хранение._прочитать(хранение._путь(путь), приватный=приватный), object_pairs_hook=без_повторов)


def приватный_путь(значение):
    путь = хранение._путь(значение)
    готовность.требовать(not any(os.path.lexists(предок / ".git") for предок in путь.parents),
                         "запись готовности запрещена внутри Git")
    return путь


def сверить(путь, снимок, поздние, сейчас, остановлено=False):
    путь = приватный_путь(путь)
    возраст = хранение._путь(str(путь) + ".возраст.json")
    замок = хранение._путь(str(путь) + ".lock")
    with os.fdopen(os.open(замок, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600), "r+b") as поток:
        хранение.чтение._обычный(os.fstat(поток.fileno()), приватный=True)
        fcntl.flock(поток, fcntl.LOCK_EX)
        сырые = хранение._прочитать(путь, приватный=True)
        запись = json.loads(сырые, object_pairs_hook=без_повторов)
        хэш = hashlib.sha256(сырые).hexdigest()
        минимум = 0
        if os.path.lexists(возраст):
            прежний = прочитать(возраст, приватный=True)
            готовность.требовать(isinstance(прежний, dict) and set(прежний) == {"схема", "готовность_sha256", "максимальный_возраст"}
                and прежний["схема"] == "fum.возраст-готового-этапа.1" and прежний["готовность_sha256"] == хэш
                and готовность.целое(прежний["максимальный_возраст"]), "неверный или чужой сохранённый возраст")
            минимум = прежний["максимальный_возраст"]
        результат = готовность.оценить(запись, снимок, поздние, сейчас, остановлено=остановлено, минимальный_возраст=минимум)
        сохранённый = {"схема": "fum.возраст-готового-этапа.1", "готовность_sha256": хэш,
                       "максимальный_возраст": результат["возраст_наносекунды"]}
        хранение.чтение._установить(возраст, (json.dumps(сохранённый, sort_keys=True, ensure_ascii=False) + "\n").encode())
        return результат


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("действие", choices=("объявить", "сверить"))
    разбор.add_argument("--снимок", type=Path, required=True)
    разбор.add_argument("--готовность", type=Path, required=True)
    разбор.add_argument("--предел-секунд", type=int)
    разбор.add_argument("--поздние-экземпляры", type=Path)
    разбор.add_argument("--остановлено", action="store_true")
    параметры = разбор.parse_args()
    try:
        снимок = прочитать(параметры.снимок)
        путь = приватный_путь(параметры.готовность)
        сейчас = time.time_ns()
        if параметры.действие == "объявить":
            if параметры.поздние_экземпляры is not None or параметры.остановлено:
                raise ValueError("поздний ввод и остановка относятся к сверке")
            прежняя = прочитать(путь, приватный=True) if os.path.lexists(путь) else None
            результат = готовность.объявить(снимок, сейчас, параметры.предел_секунд, прежняя=прежняя)
            if прежняя is None:
                хранение.сохранить_сообщение(путь, json.dumps(результат, ensure_ascii=False, sort_keys=True) + "\n")
        else:
            if параметры.предел_секунд is not None:
                raise ValueError("сверка не меняет сохранённый предел ожидания")
            поздние = прочитать(параметры.поздние_экземпляры) if параметры.поздние_экземпляры else []
            результат = сверить(путь, снимок, поздние, сейчас, остановлено=параметры.остановлено)
        print(json.dumps(результат, ensure_ascii=False, sort_keys=True))
        return 0
    except (OSError, ValueError, TypeError) as ошибка:
        print(json.dumps({"ошибка": str(ошибка), "повтор_требует_сверки": True}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(главная())

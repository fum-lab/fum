def синхронизировать(фд):
    os.fsync(фд)

def открыть(каталог, имя):
    return os.open(имя, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
        0o600, dir_fd=каталог)

def сохранить(каталог, имя, данные, атомарно=False):
    временное = имя + '.временный' if атомарно else имя
    фд = открыть(каталог, временное)
    try:
        позиция = 0
        while позиция < len(данные):
            число = os.write(фд, данные[позиция:])
            контракт.требовать(число > 0, 'частичная запись')
            позиция += число
        os.fchmod(фд, 0o400); синхронизировать(фд)
    finally:
        os.close(фд)
    if атомарно:
        os.link(временное, имя, src_dir_fd=каталог, dst_dir_fd=каталог, follow_symlinks=False)
        os.unlink(временное, dir_fd=каталог)
    синхронизировать(каталог)

def остановить_группу(процесс):
    # Группа принадлежит единственному Popen этой операции, а не внешнему PID.
    try:
        os.killpg(процесс.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    код = процесс.wait(timeout=5)
    предел = time.monotonic_ns() + 2_000_000_000
    while True:
        try:
            os.killpg(процесс.pid, 0)
        except ProcessLookupError:
            return код
        контракт.требовать(time.monotonic_ns() < предел,
            'остановка всей группы неизвестна; намерение сохраняется без terminal')
        time.sleep(0.01)

def наблюдать(выбор, удержанные):
    начало = time.monotonic_ns()
    контракт.пересверить(выбор, удержанные)
    слот = Path(выбор['слот'])
    # Исключительный слот W/ref/R: даже новый nonce не разрешает повтор неизвестного запуска.
    родитель = os.open(слот.parent, os.O_RDONLY | os.O_NOFOLLOW | os.O_DIRECTORY)
    try:
        os.mkdir(слот.name, 0o700, dir_fd=родитель)
        # fsync самого слота не сохраняет его запись в родительском каталоге.
        синхронизировать(родитель)
    finally:
        os.close(родитель)
    каталог = os.open(слот, os.O_RDONLY | os.O_NOFOLLOW | os.O_DIRECTORY)
    личность = os.fstat(каталог)
    контракт.требовать(личность.st_uid == os.getuid()
        and stat.S_IMODE(личность.st_mode) == 0o700, 'чужой слот')
    def сверить_слот():
        контракт.физический(str(слот), True)
        нынешний = слот.lstat()
        контракт.требовать((нынешний.st_dev, нынешний.st_ino, нынешний.st_mode, нынешний.st_uid)
            == (личность.st_dev, личность.st_ino, личность.st_mode, личность.st_uid), 'слот заменён')
    дескрипторы = {}
    процесс = None; код = None; ошибка = None; тайм_аут = False
    подготовка_код = None; наблюдатель_код = 2; завершён = False; очищен = False
    профиль = {'подготовка_нс': 0, 'процесс_нс': 0, 'сохранение_каналов_нс': 0}

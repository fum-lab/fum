"""Конечные цели и UUID из исходной постановки; без чтения ФС и Git."""
from datetime import datetime
from pathlib import PurePosixPath
import re
import unicodedata
import uuid


ИНДЕКСЫ = {'Журнал/README.md', 'Индексы/markdown-файлы-по-времени-редактирования.md'}
RAW = re.compile(r'([1-9][0-9]*)_([0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12})\.json')


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def путь(имя):
    требовать(type(имя) is str and bool(имя), 'нет конечной цели состояния')
    п = PurePosixPath(имя)
    требовать(not п.is_absolute() and п.as_posix() == имя and not имя.endswith('/')
        and not any(ч in ('.', '..') or ч.startswith('.') for ч in п.parts)
        and not any(знак in имя for знак in '\x00\r\n\\:*?[]')
        and unicodedata.normalize('NFC', имя) == имя and п.parts[0] != 'Proyekcii',
        'неканоническая цель состояния')
    return п


def уникальные(имена):
    требовать(type(имена) is list, 'цели должны быть конечным списком')
    ключи = set()
    for имя in имена:
        путь(имя)
        ключ = имя.casefold()
        требовать(ключ not in ключи, 'коллизия конечных целей состояния')
        требовать(not any(ключ.startswith(к + '/') or к.startswith(ключ + '/') for к in ключи),
            'файл является предком другой конечной цели')
        ключи.add(ключ)


def вывести_цели_состояния(*, координатор, sha256_постановки, журнал,
        первый_номер, роль, число_проверок, цели, прежние_записи):
    """Поздний selector A и SHA семантики намеренно отсутствуют во входе.

    Единственная предметная цель — expected. Пара Журнала, история модели,
    прежние RAW и будущие проверки выводятся отдельно. README и индекс
    включаются только при явном выборе. Физические байты и происхождение
    списка прежних RAW проверяет вызывающий слой.
    """
    требовать(type(координатор) is str and str(uuid.UUID(координатор)) == координатор,
        'неканонический UUID координатора')
    требовать(type(sha256_постановки) is str and re.fullmatch('[0-9a-f]{64}', sha256_постановки),
        'нужен сырой SHA исходной постановки')
    требовать(type(роль) is str and роль in {'корень', 'исполнитель'}, 'неизвестная роль расчёта')
    требовать(type(первый_номер) is int and первый_номер > 0
        and type(число_проверок) is int and число_проверок >= 0, 'неверный номер проверки')
    требовать(type(журнал) is str and re.fullmatch(
        r'[0-9]{4}(?:-[0-9]{2}){2}_[0-9]{2}(?:-[0-9]{2}){2}_MSK_[^/\\\s]+', журнал),
        'неканоническая папка Журнала')
    datetime.strptime(журнал[:19], '%Y-%m-%d_%H-%M-%S')
    папка = PurePosixPath('Журнал') / журнал
    путь(str(папка))
    обязательные = [str(папка / 'запрос.md'), str(папка / 'отчёт.md'),
        str(папка / 'материалы/история-модели.json')]
    уникальные(цели)
    предметные = [э for э in цели if э not in ИНДЕКСЫ and э not in обязательные]
    требовать(len(предметные) == 1 and not предметные[0].startswith(('Журнал/', 'Индексы/')),
        'нужна одна отдельная цель expected')
    уникальные(прежние_записи)
    каталог_RAW = папка / 'материалы/запуски-проверок'
    номера = set()
    UUID = set()
    for имя in прежние_записи:
        п = путь(имя)
        м = RAW.fullmatch(п.name)
        требовать(п.parent == каталог_RAW and м is not None, 'чужой или неверный прежний RAW')
        номер = int(м.group(1))
        идентификатор = м.group(2)
        требовать(номер < первый_номер and номер not in номера and идентификатор not in UUID,
            'коллизия или будущий номер прежнего RAW')
        номера.add(номер)
        UUID.add(идентификатор)
    проверки = []
    будущие = []
    for номер in range(первый_номер, первый_номер + число_проверок + 1):
        идентификатор = str(uuid.uuid5(uuid.UUID(координатор),
            sha256_постановки + ':' + журнал + ':' + str(номер) + ':' + роль))
        требовать(идентификатор not in UUID, 'UUID будущей проверки уже существует')
        UUID.add(идентификатор)
        запись = {'идентификатор': идентификатор, 'порядок': номер}
        будущие.append(str(каталог_RAW / f'{номер}_{идентификатор}.json'))
        if номер == первый_номер + число_проверок:
            связность = запись
        else:
            проверки.append(запись)
    итог = [*цели, *прежние_записи]
    итог.extend(э for э in обязательные if э not in цели)
    итог.extend(будущие)
    уникальные(итог)
    return {'цели': итог, 'проверки': проверки, 'связность': связность,
        'будущие_записи': будущие, 'существующие_записи': list(прежние_записи)}

"""Отдельный читающий допуск фиксированного предметного индекса базиса."""
import hashlib
import os
from pathlib import Path
import re
import stat
import subprocess
import unicodedata
ИСПОЛНИТЕЛЬ_ГИТ = 'git'  # Чистый consumer задаёт абсолютный независимо выбранный бинарник.


def требовать(условие, пояснение):
    if not условие:
        raise ValueError(пояснение)


def полный_объект(значение):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{40}', значение),
              'Нужен полный объект SHA-1 Git')
    return значение


def физический_корень(значение):
    корень = Path(значение)
    требовать(корень.is_absolute() and корень == корень.resolve()
              and not any(п.is_symlink() for п in (корень, *корень.parents)),
              'Нужен физический корень без символических ссылок')
    return корень


def гит(корень, *аргументы):
    среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_OPTIONAL_LOCKS='0', GIT_NO_REPLACE_OBJECTS='1',
                 GIT_NO_LAZY_FETCH='1', GIT_TERMINAL_PROMPT='0',
                 GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull)
    процесс = subprocess.run([ИСПОЛНИТЕЛЬ_ГИТ, '--no-optional-locks', '--no-replace-objects',
        '-c', 'core.hooksPath=' + os.devnull, '-c', 'core.fsmonitor=false',
        '-c', 'gc.auto=0', '-c', 'maintenance.auto=false',
        '-c', 'trace2.normalTarget=0', '-c', 'trace2.eventTarget=0',
        '-c', 'trace2.perfTarget=0',
        '-c', 'protocol.allow=never', '-C', str(корень), *аргументы],
        env=среда, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=20)
    требовать(процесс.returncode == 0, 'Чтение Git отказало')
    return процесс.stdout


def метаданные_файла(сведения):
    return (сведения.st_dev, сведения.st_ino, сведения.st_mode, сведения.st_nlink,
            сведения.st_size, сведения.st_mtime_ns, сведения.st_ctime_ns)


def отпечаток_пути(путь, корень):
    отпечатки = []
    for номер, часть in enumerate((путь, *путь.parents)):
        сведения = часть.lstat()
        требовать(not stat.S_ISLNK(сведения.st_mode), 'Символическая ссылка в читаемом пути')
        if номер == 0:
            требовать(stat.S_ISREG(сведения.st_mode) and сведения.st_nlink == 1,
                      'До открытия нужен единственный обычный файл')
            отпечатки.append(метаданные_файла(сведения))
        else:
            требовать(stat.S_ISDIR(сведения.st_mode), 'Родитель читаемого файла не каталог')
            отпечатки.append((сведения.st_dev, сведения.st_ino, сведения.st_mode,
                             сведения.st_ctime_ns if часть.is_relative_to(корень) else None))
    return tuple(отпечатки)


def обычные_байты(путь, снимки=None, корень=None):
    корень = путь.parent if корень is None else корень
    отпечаток = отпечаток_пути(путь, корень)
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        до = os.fstat(дескриптор)
        требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1,
                  'Нужен единственный обычный файл')
        with os.fdopen(дескриптор, 'rb', closefd=False) as поток:
            данные = поток.read()
        после = os.fstat(дескриптор)
        новый = путь.stat()
        требовать(отпечаток[0] == метаданные_файла(до) == метаданные_файла(после)
                  == метаданные_файла(новый)
                  and отпечаток_пути(путь, корень) == отпечаток,
                  'Читаемый файл изменился')
        if снимки is not None:
            снимки[путь] = (данные, отпечаток, корень)
        return данные
    finally:
        os.close(дескриптор)


def имя_индекса(сырое):
    имя = сырое.decode('utf-8')
    требовать(имя and not имя.startswith('/') and '\\' not in имя
              and all(часть not in ('', '.', '..', '.git') for часть in имя.split('/'))
              and all(ord(знак) >= 32 and ord(знак) != 127 for знак in имя)
              and unicodedata.normalize('NFC', имя) == имя,
              'Неканоническое имя в индексе')
    return имя


def объект_по_байтам(тип, данные):
    return hashlib.sha1(тип.encode('ascii') + b' ' + str(len(данные)).encode('ascii')
                        + b'\0' + данные).hexdigest()


def дерево_по_индексу(записи):
    """Вычислить обычный tree SHA-1 в памяти, без записи объектов Git."""
    корень = {}
    регистр = {}
    for запись in записи:
        части = запись['путь'].split('/')
        узел = корень
        for номер, часть in enumerate(части):
            префикс = '/'.join(части[:номер + 1])
            ключ = префикс.casefold()
            требовать(регистр.setdefault(ключ, префикс) == префикс,
                      'Регистровая коллизия в индексе')
            if номер == len(части) - 1:
                требовать(часть not in узел, 'Повтор или конфликт файла и каталога')
                узел[часть] = (запись['режим'], запись['объект'])
            else:
                узел = узел.setdefault(часть, {})
                требовать(type(узел) is dict, 'Конфликт файла и каталога')

    def вычислить(узел):
        элементы = []
        for имя, значение in узел.items():
            режим, объект = ('40000', вычислить(значение)) if type(значение) is dict else значение
            сырое_имя = имя.encode('utf-8')
            ключ = сырое_имя + (b'/' if режим == '40000' else b'')
            элементы.append((ключ, режим.encode('ascii') + b' ' + сырое_имя
                             + b'\0' + bytes.fromhex(объект)))
        return объект_по_байтам('tree', b''.join(данные for _, данные in sorted(элементы)))
    return вычислить(корень)


def собственная_гит_база(корень):
    """Закрытая граница независимой базы; linked worktree эффекта не разрешает."""
    корень = физический_корень(корень)
    адреса = гит(корень, 'rev-parse', '--absolute-git-dir', '--git-common-dir').split(b'\n')
    требовать(len(адреса) == 3 and адреса[-1] == b'' and all(адреса[:2]),
              'Нужен завершённый двухадресный ответ Git')
    каталог = физический_корень(адреса[0].decode('utf-8'))
    общий = Path(адреса[1].decode('utf-8'))
    общий = физический_корень(общий if общий.is_absolute() else корень / общий)
    требовать(каталог == общий == корень / '.git' and каталог.is_dir(),
              'Нужна собственная независимая Git-база, без общего common-dir')
    хранилище = физический_корень(каталог / 'objects')
    требовать(not os.path.lexists(хранилище / 'info/alternates'),
              'Внешние alternates не разрешены')
    for путь in (каталог, *каталог.rglob('*')):
        сведения = путь.lstat()
        требовать(сведения.st_uid == os.getuid() and not stat.S_ISLNK(сведения.st_mode)
                  and (stat.S_ISDIR(сведения.st_mode)
                       or stat.S_ISREG(сведения.st_mode) and сведения.st_nlink == 1),
                  'Хранилище не является собственной обычной физической областью')
        требовать(not сведения.st_mode & 0o022, 'Git-область доступна постороннему писателю')
    return каталог


def сверить_объекты_дерева(корень, дерево):
    """Перечитать все реальные tree/blob из собственной ODB; ничего не создавать."""
    корень = физический_корень(корень)
    собственная_гит_база(корень)
    ожидающие = [(полный_объект(дерево), 'tree')]
    итог = {}
    while ожидающие:
        объект, ожидаемый_тип = ожидающие.pop()
        if объект in итог:
            требовать(итог[объект]['тип'] == ожидаемый_тип, 'Разные типы одного объекта')
            continue
        тип = гит(корень, 'cat-file', '-t', объект).decode().strip()
        требовать(тип == ожидаемый_тип, 'Неверный или отсутствующий объект дерева')
        данные = гит(корень, 'cat-file', тип, объект)
        требовать(объект_по_байтам(тип, данные) == объект, 'Сырые байты не равны OID объекта')
        итог[объект] = {'тип': тип, 'размер': len(данные),
                       'sha256': hashlib.sha256(данные).hexdigest()}
        if тип != 'tree':
            continue
        смещение = 0
        имена = set()
        порядок = []
        while смещение < len(данные):
            пробел = данные.find(b' ', смещение)
            ноль = данные.find(b'\0', пробел + 1)
            требовать(пробел > смещение and ноль > пробел and ноль + 21 <= len(данные),
                      'Повреждена сырая запись дерева')
            режим = данные[смещение:пробел]
            сырое_имя = данные[пробел + 1:ноль]
            имя = имя_индекса(сырое_имя)
            требовать('/' not in имя and имя not in имена
                      and режим in (b'40000', b'100644', b'100755'),
                      'Неразрешённая запись дерева')
            имена.add(имя)
            порядок.append(сырое_имя + (b'/' if режим == b'40000' else b''))
            потомок = данные[ноль + 1:ноль + 21].hex()
            ожидающие.append((потомок, 'tree' if режим == b'40000' else 'blob'))
            смещение = ноль + 21
        требовать(порядок == sorted(порядок), 'Неканонический порядок записей дерева')
    собственная_гит_база(корень)
    return итог


def сверить_индекс(корень, предмет):
    """Точная читающая граница K/R1/T; не даёт права создавать коммит."""
    корень = физический_корень(корень)
    требовать(type(предмет) is dict
              and set(предмет) == {'основа', 'включение', 'дерево', 'родители'},
              'Нужен конечный предмет K/R1/T')
    for имя in ('основа', 'включение', 'дерево'):
        полный_объект(предмет[имя])
    требовать(type(предмет['родители']) is list
              and предмет['родители'] == [предмет['основа'], предмет['включение']]
              and предмет['основа'] != предмет['включение'], 'Неверные упорядоченные родители')
    требовать(гит(корень, 'rev-parse', '--show-toplevel').decode().strip() == str(корень),
              'Корень Git отличается от предметного адреса')
    каталог = физический_корень(гит(корень, 'rev-parse', '--absolute-git-dir').decode().strip())
    индекс = каталог / 'index'
    снимки = {}
    до = обычные_байты(индекс, снимки, каталог)
    слияние = обычные_байты(каталог / 'MERGE_HEAD', снимки, каталог)
    требовать(слияние == (предмет['включение'] + '\n').encode(), 'Неверный единственный MERGE_HEAD')
    требовать(гит(корень, 'rev-parse', 'HEAD').decode().strip() == предмет['основа'],
              'HEAD не равен K')
    for имя in ('основа', 'включение'):
        требовать(гит(корень, 'cat-file', '-t', предмет[имя]).strip() == b'commit',
                  'Родитель не является коммитом')
    требовать(гит(корень, 'cat-file', '-t', предмет['дерево']).strip() == b'tree',
              'T не является деревом')
    флаги = гит(корень, 'ls-files', '-v', '-z').split(b'\0')
    требовать(флаги[-1] == b'' and all(э.startswith(b'H ') for э in флаги[:-1]),
              'Индекс содержит скрывающие флаги')
    сырые = гит(корень, 'ls-files', '--stage', '-z').split(b'\0')
    требовать(сырые[-1] == b'', 'Незавершённый индексный инвентарь')
    записи = []
    for строка in сырые[:-1]:
        метаданные, сырое_имя = строка.split(b'\t', 1)
        режим, объект, стадия = метаданные.decode('ascii').split(' ')
        требовать(стадия == '0' and режим in ('100644', '100755'),
                  'Неразрешённый режим или конфликтная стадия индекса')
        имя = имя_индекса(сырое_имя)
        полный_объект(объект)
        путь = корень / имя
        рабочие = обычные_байты(путь, снимки, корень)
        требовать(объект_по_байтам('blob', рабочие) == объект,
                  'Рабочие байты отличаются от индекса')
        требовать(('100755' if путь.stat().st_mode & stat.S_IXUSR else '100644') == режим,
                  'Рабочий режим отличается от индекса')
        записи.append({'путь': имя, 'режим': режим, 'объект': объект,
                       'sha256': hashlib.sha256(рабочие).hexdigest()})
    дерево = дерево_по_индексу(записи)
    требовать(дерево == предмет['дерево'], 'Индекс не равен точному T')
    for путь, (данные, отпечаток, корень_снимка) in снимки.items():
        требовать(обычные_байты(путь, корень=корень_снимка) == данные
                  and отпечаток_пути(путь, корень_снимка) == отпечаток,
                  'Прочитанный путь изменился до завершения сверки')
    требовать(обычные_байты(индекс) == до and обычные_байты(каталог / 'MERGE_HEAD') == слияние
              and гит(корень, 'rev-parse', 'HEAD').decode().strip() == предмет['основа'],
              'Предмет изменился при читающей сверке')
    return {'дерево': дерево, 'индекс_sha256': hashlib.sha256(до).hexdigest(),
            'файлы': записи}

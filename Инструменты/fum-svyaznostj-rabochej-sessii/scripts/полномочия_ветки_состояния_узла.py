"""Один state ref; независимый ROOT ACT выбирает закреплённые полномочия."""
import hashlib
import json
from pathlib import Path
import re
import sys
import uuid

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'fum-reyestr-planirovaniya/scripts'))
import доставка_гит as гит

ВЕТКА = 'refs/heads/fum-lab/fum'
СХЕМА = 'fum.полномочия-ветки-состояния-узла.1'
ИДЕНТИЧНОСТЬ = {'узел', 'репозиторий', 'координатор', 'владелец', 'поколение_полномочий'}


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def поля(значение, ожидаемые):
    требовать(type(значение) is dict and set(значение) == ожидаемые, 'неверные поля полномочий узла')


def строка(значение):
    требовать(type(значение) is str and bool(значение.strip()), 'пустая идентичность полномочий')


def идентификатор(значение):
    требовать(type(значение) is str and str(uuid.UUID(значение)) == значение, 'неканонический UUID полномочий')


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def разобрать(данные):
    def пары(элементы):
        итог = {}
        for ключ, значение in элементы:
            требовать(ключ not in итог, 'повторный JSON-ключ полномочий')
            итог[ключ] = значение
        return итог
    return json.loads(данные, object_pairs_hook=пары)


def прочитать(корень, выбор, *, новый_эффект=True):
    """Выбор приходит из независимо закреплённого ACT, а не копии maker."""
    поля(выбор, {'коммит', 'путь', 'sha256'})
    гит.полный_объект(корень, выбор['коммит'])
    требовать(type(выбор['sha256']) is str and re.fullmatch('[0-9a-f]{64}', выбор['sha256']),
        'нет сырого SHA полномочий')
    данные = гит.объект_файла(корень, выбор['коммит'], выбор['путь'])
    требовать(len(данные) <= 1024 * 1024 and хэш(данные) == выбор['sha256'], 'подмена blob полномочий')
    полномочия = разобрать(данные)
    поля(полномочия, {'схема', 'ветка', 'хэш_корня', 'начальный_коммит', 'исходный_коммит',
        'путь', 'цели', 'контрольная_ветка'} | ИДЕНТИЧНОСТЬ)
    требовать(полномочия['схема'] == СХЕМА and полномочия['ветка'] == ВЕТКА,
        'неизвестная схема или другой state ref')
    for имя in ИДЕНТИЧНОСТЬ: строка(полномочия[имя])
    for имя in ('координатор', 'владелец'): идентификатор(полномочия[имя])
    требовать(полномочия['координатор'] != полномочия['владелец'], 'ROOT не является своим дочерним писателем')
    требовать(type(полномочия['хэш_корня']) is str and re.fullmatch('[0-9a-f]{64}', полномочия['хэш_корня']),
        'нет хэша физического дерева')
    for имя in ('начальный_коммит', 'исходный_коммит'): гит.полный_объект(корень, полномочия[имя])
    требовать(гит.предок(корень, полномочия['начальный_коммит'], полномочия['исходный_коммит']),
        'база не продолжает начальную постановку')
    контроль = полномочия['контрольная_ветка']
    требовать(type(контроль) is str and контроль.startswith('refs/heads/codex/'),
        'полномочия требуют отдельный control ref поколения')
    гит.выполнить(корень, 'check-ref-format', контроль)
    if новый_эффект:
        требовать(гит.гит(корень, 'rev-parse', '--verify', контроль) == выбор['коммит'],
            'изменилось контрольное поколение полномочий')
    цели = полномочия['цели']
    требовать(type(цели) is list and цели and all(type(э) is str for э in цели)
        and len(цели) == len(set(цели)) and полномочия['путь'] in цели,
        'нет одного expected и конечного состава')
    ключи = set()
    for имя in цели:
        адрес = Path(имя)
        требовать(имя and not адрес.is_absolute() and адрес.as_posix() == имя
            and not any(ч in ('.', '..') or ч.startswith('.') for ч in адрес.parts)
            and not имя.endswith('/') and имя.casefold() not in ключи, 'неверная конечная цель полномочий')
        ключи.add(имя.casefold())
    запросы = [э for э in цели if э.startswith('Журнал/') and Path(э).name == 'запрос.md']
    требовать(len(запросы) == 1, 'полномочия требуют ровно одну пару Журнала')
    папка = Path(запросы[0]).parent
    обязательные = {полномочия['путь'], запросы[0], str(папка/'отчёт.md'),
        str(папка/'материалы/история-модели.json')}
    служебные = обязательные | {'Журнал/README.md', 'Индексы/markdown-файлы-по-времени-редактирования.md'}
    требовать(обязательные <= set(цели) and not полномочия['путь'].startswith(('Журнал/', 'Индексы/')),
        'нет отдельного expected и обязательной пары')
    for имя in set(цели) - служебные:
        адрес = Path(имя)
        требовать(адрес.parent == папка/'материалы/запуски-проверок'
            and re.fullmatch(r'[1-9][0-9]*_[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\.json', адрес.name),
            'дополнительная предметная цель полномочий')
    return полномочия


def проверить_акт(корень, акт, *, новый_эффект=True):
    полномочия = прочитать(корень, акт['полномочия_узла'], новый_эффект=новый_эффект)
    требовать(акт['схема'] == 'fum.поручение-дочерней-контрольной-точки.2'
        and акт['ветка'] == полномочия['ветка']
        and акт['координатор'] == полномочия['координатор']
        and акт['исполнитель'] == полномочия['владелец']
        and акт['постановка']['коммит'] == полномочия['начальный_коммит']
        and акт['область'] == полномочия['цели'], 'ACT не соответствует полномочиям узла')
    return полномочия


def проверить_дерево(корень, владелец, ветка, выбор, *, исходный_коммит=None, цели=None, новый_эффект=True):
    полномочия = прочитать(корень, выбор, новый_эффект=новый_эффект)
    корень = гит.физический_корень(str(корень))
    требовать(ветка == ВЕТКА and владелец == полномочия['владелец']
        and хэш(str(корень).encode('utf-8')) == полномочия['хэш_корня'],
        'дерево, UUID или state ref отличаются от полномочий')
    if исходный_коммит is not None:
        требовать(исходный_коммит == полномочия['исходный_коммит'], 'другая исходная база полномочий')
    if цели is not None:
        требовать(set(цели) <= set(полномочия['цели']), 'цели выходят за независимые полномочия')
    return полномочия

"""Выбрать чтение сохранённого остатка по явному бюджету stdout в байтах."""
import hashlib
import json
import time
import uuid

from компактный_остаток import объект, проверить, представить, закодировать, требовать


ВЕРСИЯ = 'fum.детектор-бюджета-вывода.1'


def потребить(данные, ожидаемый_хэш, бюджет, код_производителя, *, начало=0, число=1, метки=None):
    """Вернуть выбранные байты и отдельную квитанцию, не меняя оригинал."""
    старт = time.perf_counter_ns()
    требовать(type(данные) is bytes and len(данные) <= 128 * 1024 * 1024, 'неверный или слишком большой вход')
    требовать(type(бюджет) is int and 100 <= бюджет <= 1024 * 1024, 'неверный бюджет байтов')
    требовать(type(код_производителя) is int and код_производителя in (0, 3), 'код производителя не допускает чтение')
    хэш = hashlib.sha256(данные).hexdigest()
    требовать(ожидаемый_хэш == хэш, 'не совпал ожидаемый хэш полного результата')
    превышен = len(данные) > бюджет
    разбор_завершён = time.perf_counter_ns()
    if превышен:
        значение = представить(данные, хэш, начало=начало, число=число, максимум_байтов=бюджет)
        завершён = значение['состояние']['разбор_сообщений_завершён']
        вывод = закодировать(значение)
    else:
        try:
            значение = json.loads(данные, object_pairs_hook=объект,
                parse_constant=lambda константа: требовать(False, 'неконечное число JSON'))
            сообщения, _ = проверить(значение)
            требовать(type(начало) is int and 0 <= начало <= len(сообщения), 'начало страницы за границей сообщений')
            требовать(type(число) is int and 1 <= число <= 1000, 'число сообщений должно быть от 1 до 1000')
        except (KeyError, TypeError, UnicodeError, RecursionError) as ошибка:
            raise ValueError('повреждённый полный результат') from ошибка
        завершён = значение['разбор_сообщений_завершён']
        вывод = данные
    задача = значение.get('задача')
    требовать(type(задача) is str and len(задача) == 36, 'неверная идентичность задачи')
    try:
        требовать(str(uuid.UUID(задача)) == задача, 'неканоническая идентичность задачи')
    except ValueError as ошибка:
        raise ValueError('неверная идентичность задачи') from ошибка
    требовать((код_производителя == 0) == завершён, 'код производителя противоречит состоянию')
    квитанция = {'схема': ВЕРСИЯ, 'единица': 'байты', 'область': 'stdout выбранного чтения',
        'бюджет': бюджет, 'превышен_бюджет': превышен,
        'источник': {'sha256': хэш, 'байты': len(данные), 'задача': значение['задача'],
            'код_производителя': код_производителя, 'код_передан_вызывающей_стороной': True},
        'реакция': 'компактный-остаток' if превышен else 'полный-остаток',
        'выход': {'sha256': hashlib.sha256(вывод).hexdigest(), 'байты': len(вывод)},
        'живой_источник_перепроверен': False, 'перехват_runtime': False,
        'квитанция_входит_в_бюджет': False}
    if метки is not None:
        метки.extend([{'этап': 'хэш-и-порог', 'наносекунды': разбор_завершён - старт},
            {'этап': 'выбор-и-представление', 'наносекунды': time.perf_counter_ns() - разбор_завершён}])
    return вывод, квитанция

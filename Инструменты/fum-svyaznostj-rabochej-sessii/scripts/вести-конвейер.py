#!/usr/bin/env python3
"""Назначать этапы в fuma, выдавать локальный допуск и проверять квитанции."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import stat
import sys

from сообщения_задачи import ОшибкаСообщений, прочитать_сообщения
import реестр_этапов as реестр


def _пары(пары):
    результат = {}
    for ключ, значение in пары:
        реестр.требовать(ключ not in результат, "Повторный ключ JSON запрещён")
        результат[ключ] = значение
    return результат


def _константа(значение):
    raise реестр.ОшибкаРеестра("Недопустимая константа JSON: " + значение)


def _json_вход(путь):
    путь = Path(путь).absolute()
    реестр.требовать(not путь.is_symlink(), "Символическая ссылка вместо входного JSON")
    состояние = путь.lstat()
    реестр.требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1,
                      "Ожидался обычный входной JSON без жёстких ссылок")
    try:
        return json.loads(путь.read_text(encoding="utf-8"), object_pairs_hook=_пары,
                          parse_constant=_константа)
    except (OSError, UnicodeError, json.JSONDecodeError) as ошибка:
        raise реестр.ОшибкаРеестра("Не удалось прочитать входной JSON") from ошибка


def _печать(значение):
    print(json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False))


def _аргументы():
    парсер = argparse.ArgumentParser(description=__doc__)
    команды = парсер.add_subparsers(dest="команда", required=True)

    извлечь = команды.add_parser("извлечь-события", help="получить точные ID сообщений из проверяемого JSONL")
    извлечь.add_argument("--корень-репозитория", type=Path, required=True)
    извлечь.add_argument("--исходник", type=Path, required=True)
    извлечь.add_argument("--codex-thread-id", required=True)
    извлечь.add_argument("--кэш", type=Path)
    извлечь.add_argument("--экземпляр", action="append", required=True)
    извлечь.add_argument("--перепроверить", action="store_true")

    назначить = команды.add_parser("назначить", help="зарезервировать событие и этап в ветке fuma")
    назначить.add_argument("--корень-репозитория", type=Path, required=True)
    назначить.add_argument("--событие-json", type=Path, required=True)
    назначить.add_argument("--экземпляр", required=True)
    назначить.add_argument("--этап", required=True)
    назначить.add_argument("--контракт", required=True, help="путь к уже закоммиченному контракту этапа")
    назначить.add_argument("--исполнитель", required=True, help="UUID выделенной рабочей задачи")
    назначить.add_argument("--выход", action="append", required=True)

    взять = команды.add_parser("взять", help="атомарно получить допуск в отдельной рабочей ветке")
    взять.add_argument("--корень-репозитория", type=Path, required=True)
    взять.add_argument("--путь-назначения", required=True)
    взять.add_argument("--исполнитель", required=True)

    квитанция = команды.add_parser("подготовить-квитанцию", help="захешировать заявленные результаты")
    квитанция.add_argument("--корень-репозитория", type=Path, required=True)
    квитанция.add_argument("--claim-id", required=True)

    завершить = команды.add_parser("завершить", help="проверить закоммиченные результаты и закрыть допуск")
    завершить.add_argument("--корень-репозитория", type=Path, required=True)
    завершить.add_argument("--claim-id", required=True)

    проверить = команды.add_parser("проверить", help="сверить назначения и квитанции во всех Git refs")
    проверить.add_argument("--корень-репозитория", type=Path, required=True)
    return парсер.parse_args()


def _извлечь(параметры):
    реестр.требовать(len(set(параметры.экземпляр)) == len(параметры.экземпляр),
                      "Повторный --экземпляр")
    снимок = прочитать_сообщения(
        параметры.исходник, параметры.codex_thread_id,
        корень_репозитория=параметры.корень_репозитория,
        кэш=параметры.кэш, перепроверить=параметры.перепроверить,
        без_записи=True,
    )
    выбранные = set(параметры.экземпляр)
    сообщения = {сообщение["экземпляр"]: сообщение for сообщение in снимок["сообщения"]}
    реестр.требовать(len(сообщения) == len(снимок["сообщения"]), "Неоднозначные экземпляры источника")
    реестр.требовать(выбранные <= set(сообщения), "Часть запрошенных сообщений отсутствует в снимке JSONL")
    события = [{"задача": снимок["задача"], "источник": снимок["источник"],
                "экземпляр": сообщения[экземпляр]["экземпляр"],
                "позиция": сообщения[экземпляр]["позиция"]}
               for экземпляр in параметры.экземпляр]
    for событие in события:
        реестр.проверить_событие(событие)
    результат = {"схема": "fum.события-конвейера.1", "задача": снимок["задача"],
                 "полнота_подтверждена": снимок["полнота_подтверждена"],
                 "источник_sha256": снимок["sha256"], "события": события}
    _печать(результат)
    return 0 if снимок["полнота_подтверждена"] else 3


def _выбрать_событие(путь, экземпляр):
    источник = _json_вход(путь)
    поля = {"схема", "задача", "полнота_подтверждена", "источник_sha256", "события"}
    реестр.требовать(type(источник) is dict and set(источник) == поля
                      and источник["схема"] == "fum.события-конвейера.1",
                      "Ожидался полный результат извлечения событий")
    реестр.требовать(источник["полнота_подтверждена"] is True,
                      "Нельзя назначать работу из неполного JSONL-снимка")
    реестр._uuid(источник["задача"])
    реестр._хэш(источник["источник_sha256"], "снимок JSONL")
    реестр.требовать(type(источник["события"]) is list, "Неверный список событий")
    выбранные = []
    seen = set()
    for событие in источник["события"]:
        реестр.проверить_событие(событие)
        реестр.требовать(событие["задача"] == источник["задача"], "Событие принадлежит другой задаче")
        реестр.требовать(событие["экземпляр"] not in seen, "Повтор экземпляра в снимке событий")
        seen.add(событие["экземпляр"])
        if событие["экземпляр"] == экземпляр:
            выбранные.append(событие)
    реестр.требовать(len(выбранные) == 1, "Выбранный экземпляр отсутствует или неоднозначен")
    return выбранные[0]
def выполнить():
    параметры = _аргументы()
    try:
        if параметры.команда == "извлечь-события":
            return _извлечь(параметры)
        if параметры.команда == "назначить":
            событие = _выбрать_событие(параметры.событие_json, параметры.экземпляр)
            результат = реестр.Реестр(параметры.корень_репозитория).назначить(
                событие=событие, этап=параметры.этап, контракт=параметры.контракт,
                исполнитель=параметры.исполнитель, выходы=параметры.выход,
            )
        elif параметры.команда == "взять":
            результат = реестр.Реестр(параметры.корень_репозитория).взять(
                путь_назначения_=параметры.путь_назначения, исполнитель=параметры.исполнитель,
            )
        elif параметры.команда == "подготовить-квитанцию":
            результат = реестр.Реестр(параметры.корень_репозитория).подготовить_квитанцию(параметры.claim_id)
        elif параметры.команда == "завершить":
            результат = реестр.Реестр(параметры.корень_репозитория).завершить(параметры.claim_id)
        else:
            снимок = реестр.проверить_ветки(параметры.корень_репозитория)
            завершённые = {реестр.ключ_работы(элемент["событие"], элемент["этап"])
                           for элемент in снимок["квитанции"]}
            возвращённые = {реестр.ключ_работы(элемент["событие"], элемент["этап"])
                            for элемент in реестр._квитанции_ветки(
                                параметры.корень_репозитория, "refs/heads/fuma")}
            записи = []
            for назначение in снимок["назначения"]:
                ключ = реестр.ключ_работы(назначение["событие"], назначение["этап"])
                состояние = (
                    "возвращено-в-fuma" if ключ in возвращённые else
                    "результат-в-рабочей-ветке" if ключ in завершённые else
                    "назначено"
                )
                записи.append({"задача": назначение["событие"]["задача"],
                               "событие": назначение["событие"]["экземпляр"],
                               "этап": назначение["этап"],
                               "назначение_id": назначение["назначение_id"],
                               "исполнитель": назначение["исполнитель"],
                               "состояние": состояние,
                               "путь": реестр.путь_назначения(назначение["событие"], назначение["этап"],
                                                              назначение["назначение_id"])} )
            результат = {"схема": "fum.состояние-конвейера.1", "назначения": записи,
                         "число_назначений": len(записи), "число_квитанций": len(снимок["квитанции"])}
        _печать(результат)
        return 0
    except реестр.ДубликатОбработки as ошибка:
        print(json.dumps({"ошибка": str(ошибка), "код": "дубликат-обработки"}, ensure_ascii=False), file=sys.stderr)
        return 4
    except (реестр.ОшибкаРеестра, ОшибкаСообщений, OSError, ValueError) as ошибка:
        print(json.dumps({"ошибка": str(ошибка)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(выполнить())

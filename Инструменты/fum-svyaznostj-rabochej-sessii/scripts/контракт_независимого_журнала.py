"""Замкнутые значения чистого преобразования; нет чтения внешнего состояния."""
from contextlib import contextmanager
from contextvars import ContextVar
from datetime import datetime
import hashlib
import json
from pathlib import PurePosixPath
import re
import unicodedata
import uuid

ПРЕДЕЛ_ТЕКСТА = 8 * 1024 * 1024
ПРЕДЕЛ_ПАРЫ = 64 * 1024 * 1024
_ПРЕДЕЛ_ЧИСТЫХ_ЗНАЧЕНИЙ = 65536
_ПРЕДЕЛ_СЫРОГО_ДЕРЕВА = 16 * 1024 * 1024
_ПРЕДЕЛ_ЗАПИСЕЙ_ДЕРЕВА = 65536
_ЧИСТЫЕ_ПРОВЕРКИ = ContextVar('fum.область-чистых-проверок.1', default=None)


@contextmanager
def область_чистых_проверок():
    """Каждому независимому proof — собственные ограниченные успешные значения."""
    токен = _ЧИСТЫЕ_ПРОВЕРКИ.set({'строки': set(), 'пути': set(), 'разобранное_дерево': None})
    try:
        yield
    finally:
        _ЧИСТЫЕ_ПРОВЕРКИ.reset(токен)


def проверенный_разбор_дерева(сырые, разобрать):
    """Только разбор новых равных bytes; само внешнее чтение остаётся у вызывающего."""
    кэш = _ЧИСТЫЕ_ПРОВЕРКИ.get()
    if кэш is None or type(сырые) is not bytes or len(сырые) > _ПРЕДЕЛ_СЫРОГО_ДЕРЕВА:
        return разобрать(сырые)
    прежнее = кэш['разобранное_дерево']
    if прежнее is not None and прежнее[0] is разобрать and прежнее[1] == сырые:
        return dict(прежнее[2])
    результат = разобрать(сырые)
    # Один положительный результат; ключи и значения не содержат изменяемых узлов.
    if (type(результат) is dict and len(результат) <= _ПРЕДЕЛ_ЗАПИСЕЙ_ДЕРЕВА
            and all(type(к) is str and type(з) is tuple and len(з) == 3
                    and all(type(ч) is str for ч in з) for к, з in результат.items())):
        кэш['разобранное_дерево'] = (разобрать, сырые, dict(результат))
    else:
        кэш['разобранное_дерево'] = None
    return результат


def требовать(условие, сообщение):
    if not условие:
        raise ValueError(сообщение)


def поля(значение, имена):
    требовать(type(значение) is dict and set(значение) == set(имена), 'неверные закрытые поля')


def канон(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False).encode('utf-8')


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def отпечаток(значение):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение), 'неверный SHA256')


def строка(значение):
    кэш = _ЧИСТЫЕ_ПРОВЕРКИ.get()
    if кэш is not None and type(значение) is str and значение in кэш['строки']:
        return
    требовать(type(значение) is str and 0 < len(значение.encode('utf-8')) <= 1024
        and not any(ord(знак) < 32 or ord(знак) == 127 for знак in значение), 'неверная строка метаданных')
    if кэш is not None and len(кэш['строки']) < _ПРЕДЕЛ_ЧИСТЫХ_ЗНАЧЕНИЙ:
        кэш['строки'].add(значение)


def идентичность(значение):
    строка(значение)
    требовать(str(uuid.UUID(значение)) == значение, 'неканоническая идентичность задачи')


def путь(значение):
    кэш = _ЧИСТЫЕ_ПРОВЕРКИ.get()
    if кэш is not None and type(значение) is str and значение in кэш['пути']:
        return
    строка(значение)
    разобранный = PurePosixPath(значение)
    требовать(not разобранный.is_absolute() and разобранный.as_posix() == значение
        and all(часть not in {'.', '..'} for часть in разобранный.parts)
        and '\\' not in значение and ':' not in значение, 'неверный относительный путь')
    if кэш is not None and len(кэш['пути']) < _ПРЕДЕЛ_ЧИСТЫХ_ЗНАЧЕНИЙ:
        кэш['пути'].add(значение)


def селектор(значение):
    поля(значение, {'коммит', 'путь', 'sha256'})
    требовать(type(значение['коммит']) is str
        and re.fullmatch('[0-9a-f]{40}|[0-9a-f]{64}', значение['коммит']), 'нужен полный OID')
    путь(значение['путь']); отпечаток(значение['sha256'])


def имя_журнала(значение, *, прежнее=False):
    строка(значение)
    требовать(len(значение.encode()) <= 255, 'имя Журнала слишком длинное')
    суффикс = r'(?:_[^\s/\\:]+)?' if прежнее else r'_[^\s/\\:]+'
    совпадение = re.fullmatch(r'(\d{4}-\d{2}-\d{2})_(\d{2}-\d{2}-\d{2})_MSK' + суффикс, значение)
    требовать(совпадение is not None, 'неверное имя Журнала')
    время = datetime.strptime(совпадение[1] + ' ' + совпадение[2], '%Y-%m-%d %H-%M-%S')
    путь('Журнал/' + значение + '/запрос.md')
    return время.strftime('%Y-%m-%d %H:%M:%S MSK')


def имя_журнала_2(значение):
    """Отдельный ASCII/lowercase контракт; прежний _MSK остаётся строгим."""
    строка(значение)
    требовать(len(значение.encode()) <= 255, 'имя Журнала слишком длинное')
    совпадение = re.fullmatch(r'([0-9]{4}-[0-9]{2}-[0-9]{2})_([0-9]{2}-[0-9]{2}-[0-9]{2})_msk_[a-z0-9]+(?:-[a-z0-9]+)*', значение)
    требовать(совпадение is not None, 'неверное имя Журнала.2')
    время = datetime.strptime(совпадение[1] + ' ' + совпадение[2], '%Y-%m-%d %H-%M-%S')
    путь('Журнал/' + значение + '/запрос.md')
    return время.strftime('%Y-%m-%d %H:%M:%S MSK')


def ключ_коллизии(значение):
    return unicodedata.normalize('NFC', значение).casefold()


def текст(значение):
    поля(значение, {'текст', 'sha256'})
    требовать(type(значение['текст']) is str, 'нужен дословный текст')
    байты = значение['текст'].encode('utf-8')
    требовать(0 < len(байты) <= ПРЕДЕЛ_ТЕКСТА, 'текст превышает границу')
    отпечаток(значение['sha256'])
    требовать(хэш(байты) == значение['sha256'], 'подмена дословного текста')
    return байты


def литерал(значение):
    ограда = '`' * max([3] + [len(вхождение[0]) + 1 for вхождение in re.finditer(r'`+', значение)])
    return ограда + 'text\n' + значение + ('' if значение.endswith('\n') else '\n') + ограда + '\n'


def надпись(значение):
    return re.sub(r'([\\`*{}\[\]()#+.!_|<>])', r'\\\1', значение)


def свежесть(содержание, время):
    # Точное правило канонического содержания штатной recency, без обращения к часам.
    содержание += '' if содержание.endswith('\n') else '\n'
    return (содержание + '\n<!-- FUM-MD-RECENCY:BEGIN -->\n'
        + '<!-- last-content-edit: ' + время + ' -->\n'
        + '<!-- content-sha256: sha256:' + хэш(содержание.encode()) + ' -->\n'
        + '<!-- FUM-MD-RECENCY:END -->\n').encode('utf-8')

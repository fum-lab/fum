"""Явный отзыв и повторная готовность внутри прежней постановки этапа."""
import copy
import re

import готовность_этапа as основа

ПОЛЯ = {"схема", "корень", "готов_в_наносекундах_эпохи", "предел_секунд",
        "максимальный_возраст", "поколения", "отзывы", "активное"}


def номер_запуска(снимок, цель):
    префикс = снимок["запрос"].rsplit("/", 1)[0] + "/материалы/запуски-проверок/"
    if not цель.startswith(префикс):
        return None
    имя = цель[len(префикс):]
    совпадение = re.fullmatch(r"[1-9][0-9]*_([0-9a-f-]{36})\.json", имя)
    основа.требовать(совпадение is not None and основа.точный_идентификатор(совпадение[1]),
                    "неканоническая цель записи проверки")
    return совпадение[1]


def граница(снимок):
    основа.проверить_снимок(снимок)
    отчёт = снимок["запрос"].rsplit("/", 1)[0] + "/отчёт.md"
    return {**{ключ: снимок[ключ] for ключ in ("задача", "ветка", "исходный_коммит", "запрос", "экземпляры")},
            "цели": sorted(цель for цель in снимок["разрешённые_цели"]
                           if цель != отчёт and номер_запуска(снимок, цель) is None)}


def проверить_записи(снимок, записи):
    основа.требовать(isinstance(записи, list) and bool(записи), "нет свидетельств проверок")
    основа.требовать(all(isinstance(элемент, list) and len(элемент) == 2
        and основа.точный_идентификатор(элемент[0]) and основа.точный_хэш(элемент[1]) for элемент in записи),
        "неверные идентичности записей проверок")
    номера = [элемент[0] for элемент in записи]
    основа.требовать(len(set(номера)) == len(номера) and set(снимок["проверки"]) <= set(номера),
                    "неполные или повторные записи обязательных проверок")
    for цель in снимок["разрешённые_цели"]:
        номер = номер_запуска(снимок, цель)
        основа.требовать(номер is None or номер in номера, "цель не подтверждена записью проверки")


def проверить_замены(старые, новые, замены):
    основа.требовать(isinstance(замены, dict) and set(замены) <= set(старые), "неверные замены проверок")
    ожидаемые = [замены.get(номер, номер) for номер in старые]
    основа.требовать(ожидаемые == новые and len(set(ожидаемые)) == len(ожидаемые),
                    "обязательные проверки нельзя сокращать или заменять без явного соответствия")


def проверить(состояние):
    основа.требовать(isinstance(состояние, dict) and set(состояние) == ПОЛЯ
        and состояние["схема"] == "fum.поколения-готовности-коммита.1", "неверный контракт поколений")
    основа.требовать(isinstance(состояние["корень"], str) and состояние["корень"].startswith("/")
        and "\0" not in состояние["корень"], "неверный корень готовности")
    for ключ in ("готов_в_наносекундах_эпохи", "предел_секунд", "максимальный_возраст"):
        основа.требовать(основа.целое(состояние[ключ]), "неверное время или предел")
    основа.требовать(состояние["предел_секунд"] > 0, "предел должен быть положительным")
    поколения = состояние["поколения"]
    основа.требовать(isinstance(поколения, list) and bool(поколения), "нет поколений готовности")
    for номер, поколение in enumerate(поколения):
        основа.требовать(isinstance(поколение, dict) and set(поколение) == {"снимок", "записи", "время", "замены"},
                        "неверные поля поколения")
        снимок = поколение["снимок"]
        основа.проверить_снимок(снимок); проверить_записи(снимок, поколение["записи"])
        основа.требовать(основа.целое(поколение["время"]) and поколение["время"] >= состояние["готов_в_наносекундах_эпохи"],
                        "поколение раньше первоначальной готовности")
        основа.требовать(граница(снимок) == граница(поколения[0]["снимок"]), "расширена постановка поколения")
        if номер:
            прошлое = поколения[номер - 1]
            проверить_замены(прошлое["снимок"]["проверки"], снимок["проверки"], поколение["замены"])
            основа.требовать(поколение["записи"][:len(прошлое["записи"])] == прошлое["записи"], "переписана история проверок")
        else:
            основа.требовать(поколение["замены"] == {} and поколение["время"] == состояние["готов_в_наносекундах_эпохи"],
                            "изменено начало готовности")
    отзывы = состояние["отзывы"]
    активное = состояние["активное"]
    основа.требовать(активное is None or type(активное) is int and активное == len(поколения) - 1,
                    "неверное активное поколение")
    основа.требовать(isinstance(отзывы, list) and len(отзывы) == len(поколения) - (активное is not None),
                    "неполная история отзывов")
    for номер, отзыв in enumerate(отзывы):
        основа.требовать(isinstance(отзыв, dict) and set(отзыв) == {"поколение", "основание", "время"}
            and type(отзыв["поколение"]) is int and отзыв["поколение"] == номер
            and isinstance(отзыв["основание"], str) and bool(отзыв["основание"].strip())
            and основа.целое(отзыв["время"]) and отзыв["время"] >= состояние["готов_в_наносекундах_эпохи"],
            "неверный отзыв готовности")


def обновить_возраст(состояние, сейчас):
    проверить(состояние)
    основа.требовать(основа.целое(сейчас) and сейчас >= состояние["готов_в_наносекундах_эпохи"],
                    "часы раньше первоначальной готовности")
    итог = copy.deepcopy(состояние)
    итог["максимальный_возраст"] = max(итог["максимальный_возраст"], сейчас - итог["готов_в_наносекундах_эпохи"])
    return итог


def объявить(корень, снимок, записи, сейчас, предел, прежнее=None, замены=None):
    основа.объявить(снимок, сейчас, предел)
    проверить_записи(снимок, записи)
    замены = {} if замены is None else замены
    поколение = {"снимок": copy.deepcopy(снимок), "записи": copy.deepcopy(записи), "время": сейчас,
                 "замены": copy.deepcopy(замены)}
    if прежнее is None:
        итог = {"схема": "fum.поколения-готовности-коммита.1", "корень": корень,
            "готов_в_наносекундах_эпохи": сейчас, "предел_секунд": предел, "максимальный_возраст": 0,
            "поколения": [поколение], "отзывы": [], "активное": 0}
    else:
        итог = обновить_возраст(прежнее, сейчас)
        основа.требовать(итог["корень"] == корень and итог["предел_секунд"] == предел, "корень и предел неизменны")
        прошлое = итог["поколения"][-1]
        основа.требовать(граница(снимок) == граница(прошлое["снимок"]), "исправление расширяет постановку")
        основа.требовать(записи[:len(прошлое["записи"])] == прошлое["записи"], "переписаны прежние свидетельства")
        if итог["активное"] is not None:
            основа.требовать(прошлое["снимок"] == снимок and not замены, "изменение готовности требует явного отзыва")
        else:
            проверить_замены(прошлое["снимок"]["проверки"], снимок["проверки"], замены)
            итог["поколения"].append(поколение)
            итог["активное"] = len(итог["поколения"]) - 1
    проверить(итог)
    return итог


def отозвать(состояние, номер, основание, сейчас):
    итог = обновить_возраст(состояние, сейчас)
    основа.требовать(type(номер) is int and номер == len(итог["поколения"]) - 1, "устаревший номер поколения")
    основа.требовать(isinstance(основание, str) and bool(основание.strip()), "нужно основание отзыва")
    if итог["активное"] is None:
        основа.требовать(итог["отзывы"][-1]["основание"] == основание, "повтор отзыва меняет основание")
    else:
        итог["отзывы"].append({"поколение": номер, "основание": основание, "время": сейчас})
        итог["активное"] = None
    проверить(итог)
    return итог


def оценить(состояние, снимок, сейчас, остановлено=False):
    итог = обновить_возраст(состояние, сейчас)
    запись = {"схема": "fum.граница-готового-этапа.1", "снимок": итог["поколения"][-1]["снимок"],
        "готов_в_наносекундах_эпохи": итог["готов_в_наносекундах_эпохи"], "предел_секунд": итог["предел_секунд"]}
    решение = основа.оценить(запись, снимок, [], сейчас, остановлено=остановлено,
                           минимальный_возраст=итог["максимальный_возраст"])
    if итог["активное"] is None and not остановлено:
        решение.update(действие="готовность-отозвана", фиксировать_этап=False)
    решение["поколение"] = итог["активное"]
    return итог, решение

"""Один доверенный запуск на C, внешняя запись и читающий повтор.

Наблюдаются границы, не вся жизнь процесса. Проверка сама завершает своих
фоновых писателей; игнорируемые входы и переносимость требуют отдельного ревью.
"""
import hashlib
import math
import os
from pathlib import Path
import stat

import захват_вывода as захват
from контракт_обратного_приёма import _ветка, _идентификатор, _читать, _поля
from копия_кода_обратного_приёма import _каталог
from схема_наблюдения_кандидата import проверить as проверить_наблюдение
from наблюдение_обратного_приёма import _гит, _текст, _требовать, _рабочее_состояние

СХЕМА = 'fum.проверка-кандидата-обратного-приёма.1'


def _вход(корень, кандидат, команда, задача, тайм_аут, предел_байтов):
    корень = Path(корень)
    _требовать(корень.is_absolute() and корень.resolve() == корень,
              'Нужен физический абсолютный корень кандидата')
    _ветка(кандидат, 'кандидат')
    _идентификатор(задача)
    _требовать(type(команда) is list and команда and all(
        type(а) is str and '\0' not in а for а in команда), 'Нужны точные аргументы')
    _требовать(type(тайм_аут) in (int, float) and math.isfinite(тайм_аут)
              and 0 < тайм_аут <= 3600, 'Неверный тайм-аут')
    захват.целое(предел_байтов, 0, 1073741824)
    return {'корень': str(корень), 'кандидат': dict(кандидат), 'команда': list(команда),
            'задача': задача, 'тайм_аут': тайм_аут, 'предел_байтов': предел_байтов}


def _границы(корень, коммит, дерево, ветка=None):
    _требовать(корень.resolve(strict=True) == корень
              and _текст(корень, 'rev-parse', '--show-toplevel') == str(корень),
              'Не найден физический Git-корень кандидата')
    _требовать(_текст(корень, 'rev-parse', '--show-object-format') == 'sha1',
              'Поддержан только Git SHA-1')
    _требовать(_текст(корень, 'rev-parse', 'HEAD') == коммит
              and _текст(корень, 'rev-parse', коммит + '^{tree}') == дерево,
              'Изменился коммит или дерево кандидата')
    if ветка is not None:
        _требовать(_текст(корень, 'symbolic-ref', 'HEAD') == ветка
                  and _текст(корень, 'rev-parse', '--verify', ветка) == коммит,
                  'Изменилась ветка кандидата')


def _байты_файла(корень, имя, режим, ожидаемый):
    путь = корень / os.fsdecode(имя)
    _требовать(путь.parent.resolve() == путь.parent and путь.is_relative_to(корень),
              'Ссылка или выход за корень индексного пути')
    до = путь.lstat()
    if режим == b'120000':
        _требовать(stat.S_ISLNK(до.st_mode), 'Изменён режим ссылки')
        сырые = os.fsencode(os.readlink(путь))
        хэш = hashlib.sha1(b'blob ' + str(len(сырые)).encode() + b'\0' + сырые)
    else:
        _требовать(режим in (b'100644', b'100755') and stat.S_ISREG(до.st_mode)
                  and bool(до.st_mode & stat.S_IXUSR) == (режим == b'100755'),
                  'Изменён режим индексного файла')
        хэш = hashlib.sha1(b'blob ' + str(до.st_size).encode() + b'\0')
        with путь.open('rb') as поток:
            for часть in iter(lambda: поток.read(1048576), b''):
                хэш.update(часть)
    после = путь.lstat()
    свойства = lambda с: (с.st_dev, с.st_ino, с.st_mode, с.st_size, с.st_mtime_ns, с.st_ctime_ns)
    _требовать(свойства(до) == свойства(после) and хэш.hexdigest().encode() == ожидаемый,
              'Рабочие байты не совпадают с кандидатом')


def _состояние(корень, коммит, дерево, ветка=None, глубина=0):
    _требовать(глубина < 64, 'Чрезмерная глубина Git-зависимостей')
    _границы(корень, коммит, дерево, ветка)
    индекс = _рабочее_состояние(корень)
    ожидаемые = []
    for строка in _гит(корень, 'ls-tree', '-r', '-z', '--full-tree', коммит).split(b'\0'):
        if строка:
            мета, имя = строка.split(b'\t', 1)
            режим, _, объект = мета.split()
            ожидаемые.append(режим + b' ' + объект + b' 0\t' + имя)
    ожидаемые.sort(key=lambda с: с.split(b'\t', 1)[1])
    stage0 = b'\0'.join(ожидаемые) + (b'\0' if ожидаемые else b'')
    _требовать(_гит(корень, 'ls-files', '--stage', '-z') == stage0,
              'Индекс отличается от дерева кандидата')
    зависимости = []
    for строка in ожидаемые:
        мета, имя = строка.split(b'\t', 1)
        режим, объект, _ = мета.split()
        if режим == b'160000':
            вложенный = корень / os.fsdecode(имя)
            _требовать(вложенный.resolve() == вложенный and вложенный.is_relative_to(корень)
                      and os.path.lexists(вложенный / '.git'),
                      'Git-зависимость не инициализирована')
            поддерево = _текст(вложенный, 'rev-parse', объект.decode() + '^{tree}')
            зависимости.append({'путь': os.fsdecode(имя), 'состояние': _состояние(
                вложенный, объект.decode(), поддерево, глубина=глубина + 1)})
        else:
            _байты_файла(корень, имя, режим, объект)
    _требовать(_гит(корень, 'ls-files', '--stage', '-z') == stage0
              and _рабочее_состояние(корень) == индекс, 'Кандидат изменился во время наблюдения')
    _границы(корень, коммит, дерево, ветка)
    return {'корень': str(корень), 'коммит': коммит, 'дерево': дерево,
            'ветка': ветка, 'индекс_sha256': захват.хэш(stage0), 'зависимости': зависимости}


def _наблюдать(вход):
    к = вход['кандидат']
    return _состояние(Path(вход['корень']), к['коммит'], к['дерево'], к['ветка'])


def _успех(манифест):
    return (манифест['полнота'] is True and type(манифест['код_процесса']) is int
            and манифест['код_процесса'] == 0 and манифест['причина'] is None
            and all(к['конец'] is True for к in манифест['каналы'].values()))


def запустить(корень, кандидат, команда, задача, каталог, *, тайм_аут=60,
              предел_байтов=134217728):
    вход = _вход(корень, кандидат, команда, задача, тайм_аут, предел_байтов)
    каталог = _каталог(каталог)
    _требовать(not os.path.lexists(каталог), 'Каталог результата уже существует; повтор запуска запрещён')
    до = _наблюдать(вход)
    каталог.mkdir(mode=0o700)
    захват.синхронизировать_каталог(каталог.parent)
    захват.сохранить(каталог / 'намерение.json', захват.закодировать(вход))
    захват.сохранить(каталог / 'до.json', захват.закодировать(до))
    захват.синхронизировать_каталог(каталог)
    # Исключение захвата оставляет намерение и частичный поток, без успешного результата.
    манифест, отпечаток = захват.захватить_с_хэшем(команда, каталог / 'процесс', корень,
        задача, тайм_аут=тайм_аут, предел_байтов=предел_байтов, обработчик='общий')
    ошибка = None
    try:
        после = _наблюдать(вход)
    except (ValueError, OSError) as исключение:
        после = None
        ошибка = str(исключение)
    результат = {'схема': СХЕМА, 'вход': вход, 'до': до, 'после': после,
                 'процесс_sha256': отпечаток, 'ошибка': ошибка,
                 'пригоден': ошибка is None and до == после and _успех(манифест),
                 'разрешение_записи': False}
    сырые = захват.закодировать(результат)
    захват.сохранить(каталог / 'результат.json', сырые)
    захват.синхронизировать_каталог(каталог)
    return {'sha256': захват.хэш(сырые), 'результат': результат}


def прочитать(каталог, ожидаемый_sha256, ожидаемый_вход):
    """Проверить сохранённые байты, не запуская процесс и не обращаясь к HEAD."""
    каталог = _каталог(каталог)
    вход = _вход(**ожидаемый_вход)
    with захват.открыть_обычный(каталог / 'результат.json') as поток:
        сырые = поток.read(4194305)
    _требовать(len(сырые) <= 4194304, 'Слишком большой результат проверки')
    результат = _читать(сырые, ожидаемый_sha256, 'результат')
    _поля(результат, 'схема вход до после процесс_sha256 ошибка пригоден разрешение_записи', 'результат')
    _требовать(результат['схема'] == СХЕМА and результат['вход'] == вход
              and результат['пригоден'] is True and результат['ошибка'] is None
              and результат['разрешение_записи'] is False, 'Не подтверждён успешный результат этого входа')
    до, после = результат['до'], результат['после']
    проверить_наблюдение(до, вход['корень'])
    к = вход['кандидат']
    _требовать(type(до) is dict and до == после and до.get('корень') == вход['корень']
              and all(до.get(п) == к[п] for п in ('коммит', 'дерево', 'ветка')),
              'Наблюдения не связывают выбранный кандидат')
    for имя, значение in (('намерение.json', вход), ('до.json', до)):
        with захват.открыть_обычный(каталог / имя) as поток:
            _требовать(поток.read(4194305) == захват.закодировать(значение), 'Изменена исходная запись')
    процесс = каталог / 'процесс'
    _, манифест = захват.прочитать_манифест(процесс, результат['процесс_sha256'])
    _требовать(sum(к['байты'] for к in манифест['каналы'].values()) <= вход['предел_байтов'],
              'Сохранённые каналы превышают выбранный общий предел')
    вызов = {'команда': вход['команда'], 'корень': вход['корень'], 'задача': вход['задача'],
             'тайм_аут': вход['тайм_аут'], 'предел_байтов': вход['предел_байтов'],
             'обработчик': 'общий', 'оболочка': False, 'автоматический_повтор': False}
    with захват.открыть_обычный(процесс / 'вызов.json') as поток:
        сырые_вызова = поток.read(4194305)
    _требовать(сырые_вызова == захват.закодировать(вызов)
              and захват.хэш(сырые_вызова) == манифест['вызов_sha256']
              and манифест['задача'] == вход['задача'] and _успех(манифест),
              'Исход процесса или его вызов не совпали')
    for канал in ('stdout', 'stderr'):
        захват.прочитать_диапазон(процесс, результат['процесс_sha256'], канал, 0, 0, 4096)
    return результат

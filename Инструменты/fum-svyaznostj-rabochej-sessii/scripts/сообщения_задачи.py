class ОшибкаСообщений(ValueError):
    """Полнота не доказана; пустой остаток и допуск не возвращаются."""


class ОшибкаСлужебнойОболочки(ОшибкаСообщений):
    """Статическая причина отказа без значений нативной записи."""


def _требовать(условие, пояснение):
    if not условие:
        raise ОшибкаСообщений(пояснение)


def _хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def _байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode("utf-8")


def _пары(пары):
    результат = {}
    for ключ, значение in пары:
        _требовать(ключ not in результат, "повторный ключ JSON")
        результат[ключ] = значение
    return результат


def _запретить_константу(значение):
    raise ОшибкаСообщений("специальное число JSON запрещено")


def _разобрать(байты):
    try:
        результат = json.loads(байты.decode("utf-8"), object_pairs_hook=_пары, parse_constant=_запретить_константу)
        # Не допускаем одиночные суррогаты и нечисловые значения после разбора.
        _байты(результат)
        return результат
    except (ValueError, UnicodeError, RecursionError) as ошибка:
        raise ОшибкаСообщений("повреждённый JSON") from ошибка


def _путь(значение):
    путь = Path(значение).absolute()
    _требовать(not путь.is_symlink(), "символическая ссылка вместо файла")
    return путь.parent.resolve() / путь.name


def _обычный(состояние, *, приватный=False):
    _требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1, "ожидался обычный файл без жёстких ссылок")
    if приватный:
        _требовать(состояние.st_uid == os.getuid() and состояние.st_mode & 0o077 == 0, "приватный файл доступен другому пользователю")


def _метка(состояние):
    return [состояние.st_dev, состояние.st_ino, состояние.st_size, состояние.st_mtime_ns, состояние.st_ctime_ns]


@contextmanager
def _замок(путь):
    # Отдельный неизменяемый inode: replace файла данных не снимает этот замок.
    дескриптор = os.open(str(путь) + ".lock", os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    try:
        _обычный(os.fstat(дескриптор), приватный=True)
        fcntl.flock(дескриптор, fcntl.LOCK_EX)
        yield
    finally:
        os.close(дескриптор)


def _установить(путь, данные):
    временный = None
    try:
        with tempfile.NamedTemporaryFile(dir=путь.parent, prefix=".сообщения-", delete=False) as поток:
            временный = Path(поток.name)
            поток.write(данные)
            поток.flush()
            os.fsync(поток.fileno())
        os.replace(временный, путь)
        каталог = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(каталог)
        finally:
            os.close(каталог)
    finally:
        if временный is not None:
            временный.unlink(missing_ok=True)


def _кэш_прочитать(путь, задача):
    if not путь.exists():
        return None
    with путь.open("rb") as поток:
        _обычный(os.fstat(поток.fileno()), приватный=True)
        оболочка = _разобрать(поток.read())
    _требовать(type(оболочка) is dict and set(оболочка) == {"данные", "sha256"}, "неверный кэш")
    данные = оболочка["данные"]
    _требовать(_хэш(_байты(данные)) == оболочка["sha256"], "хэш кэша не совпал")
    _требовать(type(данные) is dict and set(данные) == {"схема", "задача", "источник", "метка", "граница", "sha256", "сообщения", "транспорт", "реализация"}, "неверная схема кэша")
    _требовать(данные["схема"] == _СХЕМА and данные["задача"] == задача, "чужой кэш")
    _требовать(type(данные["граница"]) is int and данные["граница"] > 0 and type(данные["сообщения"]) is list and type(данные["транспорт"]) is dict, "повреждённый индекс")
    return данные


def _форма_дополнительных_инструментов(данные):
    if (set(данные) != {"type", "id", "role", "tools"}
            or данные["role"] != "developer" or type(данные["id"]) is not str or not данные["id"]
            or type(данные["tools"]) is not list or not данные["tools"]):
        return False
    for группа in данные["tools"]:
        if type(группа) is dict and группа.get("type") == "tool_search":
            if (set(группа) != {"type", "execution", "description", "parameters"}
                    or группа["execution"] != "client" or type(группа["description"]) is not str
                    or type(группа["parameters"]) is not dict):
                return False
            continue
        if (type(группа) is not dict or set(группа) != {"type", "name", "description", "tools"}
                or группа["type"] != "namespace" or type(группа["name"]) is not str or not группа["name"]
                or type(группа["description"]) is not str or type(группа["tools"]) is not list or not группа["tools"]):
            return False
        for инструмент in группа["tools"]:
            if (type(инструмент) is not dict or type(инструмент.get("name")) is not str or not инструмент["name"]
                    or type(инструмент.get("description")) is not str):
                return False
            if инструмент.get("type") == "function":
                if (set(инструмент) != {"type", "name", "description", "parameters", "strict"}
                        or type(инструмент["parameters"]) is not dict or type(инструмент["strict"]) is not bool):
                    return False
            elif инструмент.get("type") == "custom":
                if set(инструмент) != {"type", "name", "description", "format"}:
                    return False
                формат = инструмент["format"]
                if (type(формат) is not dict or set(формат) != {"type", "syntax", "definition"}
                        or формат["type"] != "grammar" or формат["syntax"] != "lark"
                        or type(формат["definition"]) is not str or not формат["definition"]):
                    return False
            else:
                return False
    return True


def _добавить_сообщение(индекс, запись, сырая, начало, конец):
    if запись.get("type") != "response_item":
        return
    данные = запись.get("payload")
    _требовать(type(данные) is dict and type(данные.get("type")) is str and bool(данные["type"]), "повреждённая оболочка response_item")
    if данные["type"] == "additional_tools":
        if not _форма_дополнительных_инструментов(данные):
            raise ОшибкаСлужебнойОболочки("неверная форма служебной оболочки additional_tools")
        return
    if данные["type"] != "message":
        if "role" in данные:
            raise ОшибкаСлужебнойОболочки("роль в неизвестной оболочке response_item")
        return
    _требовать(данные.get("role") in {"user", "assistant", "system", "developer", "tool"}, "неизвестная роль сообщения")
    if данные["role"] != "user":
        return
    происхождение = _КЛАССИФИКАТОР.классифицировать_сообщение(данные)
    служебное = происхождение in {"служебный hook", "служебный контекст"}
    позиция = {"начало": начало, "конец": конец, "sha256": _хэш(сырая)}
    транспорт = данные.get("id")
    отпечаток = _хэш(_байты(данные))
    if type(транспорт) is str and транспорт:
        прежний = индекс["транспорт"].get(транспорт)
        if прежний is not None:
            _требовать(прежний["sha256"] == отпечаток, "противоречащие представления транспортного сообщения")
            if прежний["номер"] is not None:
                индекс["сообщения"][прежний["номер"]]["дубли"].append(позиция)
            return
        индекс["транспорт"][транспорт] = {"sha256": отпечаток, "номер": None if служебное else len(индекс["сообщения"])}
    if служебное:
        return
    экземпляр = _хэш(_байты({"задача": индекс["задача"], "источник": индекс["источник"], **позиция}))
    индекс["сообщения"].append({"экземпляр": экземпляр, "позиция": позиция,
        "происхождение": происхождение, "содержимое": данные.get("content"),
        "сырой_объект": copy.deepcopy(данные), "дубли": []})


def _прочитать_поток(поток, задача, прежний, *, только_хвост=False, предел):
    индекс = {"схема": _СХЕМА, "задача": задача, "источник": None, "метка": None,
              "граница": 0, "sha256": None, "сообщения": [], "транспорт": {}, "реализация": _РЕАЛИЗАЦИЯ}
    хэширование = hashlib.sha256()
    сверка = прежний is None
    байтов = 0
    строк = 0
    if только_хвост:
        _требовать(прежний["граница"] <= предел, "прочитанный префикс усечён")
        остаток = прежний["граница"]
        while остаток:
            блок = поток.read(min(остаток, 1024 * 1024))
            _требовать(bool(блок), "прочитанный префикс усечён")
            хэширование.update(блок)
            остаток -= len(блок)
            байтов += len(блок)
        _требовать(хэширование.hexdigest() == прежний["sha256"], "ранее прочитанный префикс изменён")
        индекс = copy.deepcopy(прежний)
        сверка = True
    while True:
        начало = поток.tell()
        if начало >= предел:
            break
        сырая = поток.readline(min(_МАКСИМУМ_СТРОКИ + 1, предел - начало))
        байтов += len(сырая)
        _требовать(len(сырая) <= _МАКСИМУМ_СТРОКИ, "строка превышает ограничение 64 МиБ")
        if not сырая or not сырая.endswith(b"\n"):
            break
        запись = _разобрать(сырая)
        _требовать(type(запись) is dict, "строка JSONL не объект")
        строк += 1
        if начало == 0:
            _требовать(запись.get("type") == "session_meta" and type(запись.get("payload")) is dict and запись["payload"].get("id") == задача, "неверный источник задачи")
            индекс["источник"] = _хэш(сырая)
        else:
            _требовать(запись.get("type") != "session_meta", "повторная идентичность задачи")
        конец = начало + len(сырая)
        хэширование.update(сырая)
        индекс["граница"] = конец
        if прежний is not None and конец == прежний["граница"]:
            _требовать(хэширование.hexdigest() == прежний["sha256"] and индекс["источник"] == прежний["источник"], "ранее прочитанный префикс изменён")
            сверка = True
        _добавить_сообщение(индекс, запись, сырая, начало, конец)
    _требовать(индекс["источник"] is not None, "нет законченного session_meta")
    _требовать(сверка, "прочитанный префикс усечён или изменён")
    индекс["sha256"] = хэширование.hexdigest()
    return индекс, {"прочитано_байтов": байтов, "разобрано_строк": строк, "режим": "проверенный префикс и хвост" if только_хвост else "полный"}


def _сверить_снимок(поток, исходник, состояние, индекс, *, предел_снимка=None):
    предел = состояние.st_size if предел_снимка is None else предел_снимка
    _требовать(type(предел) is int and 0 <= предел <= состояние.st_size,
               "источник усечён относительно закреплённого снимка")

    def наблюдать():
        открытое = os.fstat(поток.fileno())
        текущее = исходник.stat()
        _обычный(открытое)
        _обычный(текущее)
        _требовать((состояние.st_dev, состояние.st_ino) == (открытое.st_dev, открытое.st_ino) == (текущее.st_dev, текущее.st_ino), "источник заменён во время чтения")
        _требовать(min(открытое.st_size, текущее.st_size) >= состояние.st_size, "источник усечён во время чтения")
        return открытое, текущее

    открытое, текущее = наблюдать()
    байтов = 0
    if _метка(состояние) != _метка(открытое) or _метка(состояние) != _метка(текущее):
        остаток = индекс["граница"]
        смещение = 0
        хэширование = hashlib.sha256()
        while остаток:
            блок = os.pread(поток.fileno(), min(остаток, 1024 * 1024), смещение)
            _требовать(bool(блок), "прочитанный префикс усечён")
            хэширование.update(блок)
            остаток -= len(блок)
            смещение += len(блок)
            байтов += len(блок)
        _требовать(хэширование.hexdigest() == индекс["sha256"], "прочитанный префикс изменён во время чтения")
        открытое, текущее = наблюдать()
    return текущее.st_size - предел, байтов


def _сверить_закреплённый_снимок(поток, исходник, состояние, индекс, идентичность,
                                конец, ожидаемый_хвост=None, *, проверить_префикс=False):
    """Заключительно проверить прежние диапазоны одного открытого inode."""
    начало = индекс["граница"]
    _требовать(type(начало) is int and type(конец) is int and 0 <= начало <= конец,
               "повреждена граница закреплённого снимка")
    размеры = [состояние.st_size]

    def наблюдать():
        открытое = os.fstat(поток.fileno())
        путь = исходник.stat()
        _обычный(открытое)
        _обычный(путь)
        _требовать((открытое.st_dev, открытое.st_ino) == (путь.st_dev, путь.st_ino) == идентичность,
                   "источник заменён при сверке закреплённого снимка")
        _требовать(min(открытое.st_size, путь.st_size) >= состояние.st_size,
                   "источник усечён во время сверки закреплённого снимка")
        размеры.extend((открытое.st_size, путь.st_size))
        return открытое, путь

    прочитано = 0
    def хэш_диапазона(от, до):
        nonlocal прочитано
        хэширование = hashlib.sha256()
        смещение = от
        while смещение < до:
            блок = os.pread(поток.fileno(), min(до - смещение, 1024 * 1024), смещение)
            _требовать(bool(блок), "источник усечён относительно закреплённого снимка")
            хэширование.update(блок)
            смещение += len(блок)
            прочитано += len(блок)
        return хэширование.hexdigest()

    до_сверки = наблюдать()
    хвост = хэш_диапазона(начало, конец)
    _требовать(ожидаемый_хвост is None or хвост == ожидаемый_хвост,
               "неполный хвост первого снимка изменён")
    после_хвоста = наблюдать()
    дрейф = (any(_метка(э) != _метка(состояние) for э in до_сверки + после_хвоста)
              or any(_метка(э) != _метка(до_сверки[0]) for э in после_хвоста))
    if проверить_префикс or дрейф:
        _требовать(хэш_диапазона(0, начало) == индекс["sha256"],
                   "прочитанный префикс изменён при закреплённой сверке")
    if дрейф:
        повторный_хвост = хэш_диапазона(начало, конец)
        _требовать(повторный_хвост == хвост and
                   (ожидаемый_хвост is None or повторный_хвост == ожидаемый_хвост),
                   "неполный хвост первого снимка изменён")
    финал = наблюдать()
    поздний_рост = False
    for прежнее, текущее in zip(после_хвоста, финал):
        if _метка(прежнее) != _метка(текущее):
            _требовать(текущее.st_size > прежнее.st_size,
                       "источник изменён после хэширования закреплённого снимка")
            поздний_рост = True
    if поздний_рост:
        _требовать(хэш_диапазона(0, начало) == индекс["sha256"],
                   "прочитанный префикс изменён при позднем росте")
        _требовать(хэш_диапазона(начало, конец) == хвост,
                   "неполный хвост первого снимка изменён при позднем росте")
        подтверждение = наблюдать()
        for прежнее, текущее in zip(финал, подтверждение):
            if _метка(прежнее) != _метка(текущее):
                _требовать(текущее.st_size > прежнее.st_size,
                           "источник изменён после повторного хэширования закреплённого снимка")
    # Любое уже замеченное увеличение того же inode запрещает ложную полноту.
    return хвост, max(размеры) - конец, прочитано


def прочитать_сообщения(источник, задача, *, корень_репозитория, кэш=None, перепроверить=False, без_записи=False):
    """Одно чтение; индекс другого вызова не остаётся в глобальной памяти."""
    return _сеанс_чтения(источник, задача, корень_репозитория=корень_репозитория,
        кэш=кэш, перепроверить=перепроверить, без_записи=без_записи)()


class _СеансЧтения:
    """Прежний закрытый индекс с проверяемой привязкой одной операции."""
    def __init__(сам, источник, задача, **параметры):
        try:
            сам.закрепить_первый_снимок = параметры.pop("закрепить_первый_снимок", False)
            _требовать(type(сам.закрепить_первый_снимок) is bool,
                       "признак закрепления первого снимка должен быть логическим")
            _требовать(not сам.закрепить_первый_снимок or параметры.get("без_записи") is True,
                       "закрепление первого снимка разрешено только без записи")
            сам.источник = Path(источник).absolute()
            сам.задача = задача
            сам.параметры = {"кэш": None, "перепроверить": False, "без_записи": False, **параметры}
            сам.параметры["корень_репозитория"] = Path(сам.параметры["корень_репозитория"]).resolve()
            сам.прежний = None
            сам.предел_первого_снимка = None
            сам.идентичность_первого_снимка = None
            сам.хэш_неполного_хвоста = None
            сам.наибольший_замеченный_размер = None
        except (OSError, ValueError, TypeError) as ошибка:
            raise ОшибкаСообщений("источник или локальное состояние недоступны либо повреждены") from ошибка

    def соответствует(сам, источник, задача, **параметры):
        закрепить = параметры.pop("закрепить_первый_снимок", False)
        ожидаемые = {"кэш": None, "перепроверить": False, "без_записи": False, **параметры}
        ожидаемые["корень_репозитория"] = Path(ожидаемые["корень_репозитория"]).resolve()
        return (сам.источник == Path(источник).absolute() and сам.задача == задача
                and сам.параметры == ожидаемые and сам.закрепить_первый_снимок == закрепить)

    def __call__(сам):
        результат, сам.прежний, хэш_хвоста = _прочитать_снимок(сам.источник, сам.задача,
            **сам.параметры, прежний=сам.прежний,
            предел_снимка=сам.предел_первого_снимка if сам.закрепить_первый_снимок else None,
            ожидаемая_идентичность=сам.идентичность_первого_снимка,
            закрепить_первый_снимок=сам.закрепить_первый_снимок,
            ожидаемый_хэш_неполного_хвоста=сам.хэш_неполного_хвоста)
        if сам.закрепить_первый_снимок and сам.предел_первого_снимка is None:
            сам.предел_первого_снимка = результат["размер_снимка"]
            сам.идентичность_первого_снимка = tuple(сам.прежний["метка"][:2])
        if сам.закрепить_первый_снимок and сам.хэш_неполного_хвоста is None:
            сам.хэш_неполного_хвоста = хэш_хвоста
        if сам.закрепить_первый_снимок:
            замеченный_размер = (результат["размер_снимка"]
                                  + результат["дописано_после_снимка"])
            _требовать(сам.наибольший_замеченный_размер is None
                       or замеченный_размер >= сам.наибольший_замеченный_размер,
                       "источник усечён относительно ранее замеченного роста")
            сам.наибольший_замеченный_размер = замеченный_размер
        return результат



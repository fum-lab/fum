"""P.2: expected/ACT/решения из Git, без текущего checkout и наблюдения API."""
from pathlib import PurePosixPath
import unicodedata

import состояние_задач_узла as состояние
import полномочия_ветки_состояния_узла as полномочия
import историческая_доставка_ожиданий as доставка

канон = состояние.канон


def _прочитать(корень, выбор):
    канон.источник(выбор)
    return доставка.прочитать_источник(корень, выбор)


def _акт(корень, выбор, координатор, исполнитель):
    канон.обычное_поручение.выбор(выбор)
    _нескрытый(выбор['путь'])
    канон.требовать((выбор['координатор'], выбор['исполнитель']) == (координатор, исполнитель),
        'чужой исторический выбор ACT')
    акт = канон.разобрать(_прочитать(корень, {к: выбор[к] for к in ('коммит', 'путь', 'sha256')}))
    канон.требовать(type(акт) is dict, 'нужен объект исторического ACT')
    новый = акт.get('схема') == 'fum.поручение-дочерней-контрольной-точки.2'
    канон.поля(акт, {'схема', 'координатор', 'исполнитель', 'ветка', 'область', 'постановка',
        'хэш_нативного_поручения'} | ({'полномочия_узла'} if новый else set()))
    канон.требовать(новый or акт['схема'] == 'fum.поручение-дочерней-контрольной-точки.1',
        'неизвестная схема исторического ACT')
    канон.требовать((акт['координатор'], акт['исполнитель']) == (координатор, исполнитель),
        'чужие UUID исторического ACT')
    канон.источник(акт['постановка']); _нескрытый(акт['постановка']['путь'])
    _прочитать(корень, акт['постановка']); канон.полный_хэш(акт['хэш_нативного_поручения'])
    области = акт['область']; ключи = set()
    канон.требовать(type(области) is list and области, 'пустая историческая область ACT')
    for имя in области:
        канон.строка(имя); путь = имя.removesuffix('/'); _нескрытый(путь)
        ключ = unicodedata.normalize('NFC', путь).casefold()
        канон.требовать(ключ not in ключи, 'повтор исторической области ACT'); ключи.add(ключ)
    канон.относительный_путь(акт['ветка'])
    полномочия.гит.выполнить(корень, 'check-ref-format', акт['ветка'])
    if новый:
        источник = акт['полномочия_узла']; канон.источник(источник)
        _нескрытый(источник['путь'])
        размер = int(полномочия.гит.гит(корень, 'cat-file', '-s',
            источник['коммит']+':'+источник['путь']))
        канон.требовать(0 < размер <= 1024*1024, 'исторические полномочия превышают границу')
        полномочия.проверить_акт(корень, акт, новый_эффект=False)
        канон.требовать(полномочия.гит.предок(корень, акт['полномочия_узла']['коммит'], выбор['коммит']),
            'исторические полномочия не предшествуют ACT')
    else:
        канон.требовать(акт['ветка'].startswith('refs/heads/codex/'), 'неверный исторический ref ACT')
    return акт


def _нескрытый(путь):
    канон.обычное_поручение.история.точный_путь(путь)
    канон.требовать(not any(э.startswith('.') for э in PurePosixPath(путь).parts), 'скрытый путь ACT')


def проверить(данные, идентичность, *, корень):
    ожидания = канон.разобрать(данные)
    канон.поля(ожидания, {'схема', 'основание', 'предпросмотр'} | состояние.ИДЕНТИЧНОСТЬ)
    канон.требовать(ожидания['схема'] == 'fum.ожидаемое-состояние-узла.1'
        and all(ожидания[к] == идентичность[к] for к in состояние.ИДЕНТИЧНОСТЬ), 'чужой expected')
    _прочитать(корень, ожидания['основание'])
    вход = ожидания['предпросмотр']
    канон.поля(вход, {'схема', 'координатор', 'постановка_выбора', 'полнота_перечня', 'исполнители'})
    канон.требовать(вход['схема'] == 'fum.вход-предпросмотра-продолжения.2'
        and вход['координатор'] == идентичность['координатор']
        and type(вход['полнота_перечня']) is bool and type(вход['исполнители']) is list, 'неверный исторический перечень')
    _прочитать(корень, вход['постановка_выбора']); задачи = set()
    for актёр in вход['исполнители']:
        канон.поля(актёр, {'задача', 'хост', 'владелец', 'поручение', 'решение_координатора',
            'снимок', 'доставка', 'необязательная_инфраструктура'})
        for имя in ('задача', 'владелец'): канон.идентичность(актёр[имя])
        канон.строка(актёр['хост'])
        канон.требовать(актёр['задача'] not in задачи and актёр['снимок'] is None
            and type(актёр['необязательная_инфраструктура']) is bool, 'повтор или live-наблюдение в expected')
        задачи.add(актёр['задача'])
        _акт(корень, актёр['поручение'], вход['координатор'], актёр['задача'])
        решение = канон.разобрать(_прочитать(корень, актёр['решение_координатора']))
        канон.решение_координатора(решение)
        канон.требовать((решение['координатор'], решение['задача'], решение['хост']) ==
            (вход['координатор'], актёр['задача'], актёр['хост']), 'чужая идентичность решения ROOT')
        if решение['результат'] is not None: _прочитать(корень, решение['результат']['источник'])
        if актёр['доставка'] is not None:
            доставка.проверить(актёр['доставка'], корень=корень, координатор=вход['координатор'],
                задача=актёр['задача'], идентификатор=решение['план_доставки'])
    return ожидания

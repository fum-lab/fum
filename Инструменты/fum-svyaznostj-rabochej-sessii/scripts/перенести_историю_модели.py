"""Проверенный перенос истории модели между двумя этапами одного checkout."""
import os
import time
import uuid
from contextlib import ExitStack

import история_модели as модель
from перепривязать_историю_модели import прочитать_подтверждённую_историю


чтение = модель.чтение


def _сверить_последнее_наблюдение(поток, прежняя):
    """Проверить используемую для следующего перехода пару по исходной строке."""
    последнее = прежняя["последнее"]
    if последнее is None:
        return
    чтение._требовать(type(последнее) is dict and set(последнее) == {
        "модель", "усилие", "время", "позиция", "причина", "инициатор"},
        "повреждено последнее наблюдение")
    позиция = последнее["позиция"]
    чтение._требовать(type(позиция) is dict and set(позиция) == {
        "начало", "конец", "sha256"} and
        type(позиция["начало"]) is int and type(позиция["конец"]) is int and
        0 <= позиция["начало"] < позиция["конец"] <= прежняя["граница"] and
        позиция["конец"] - позиция["начало"] <= чтение._МАКСИМУМ_СТРОКИ,
        "повреждена позиция последнего наблюдения")
    прежнее_смещение = поток.tell()
    поток.seek(позиция["начало"])
    строка = поток.read(позиция["конец"] - позиция["начало"])
    чтение._требовать(строка.endswith(b"\n") and чтение._хэш(строка) == позиция["sha256"],
        "строка последнего наблюдения не совпадает")
    запись = чтение._разобрать(строка)
    полезная_нагрузка = запись.get("payload") if isinstance(запись, dict) else None
    чтение._требовать(isinstance(запись, dict) and запись.get("type") == "turn_context" and
        isinstance(полезная_нагрузка, dict) and
        (запись.get("timestamp"), полезная_нагрузка.get("model"), полезная_нагрузка.get("effort")) ==
        (последнее["время"], последнее["модель"], последнее["усилие"]),
        "последнее наблюдение не совпадает с исходной строкой")
    поток.seek(прежнее_смещение)


def перенести(источник, задача, *, корень_репозитория, прежний_кэш,
             прежняя_история, кэш, история, без_записи=False):
    """Создать новую пару, подтвердив байты старого префикса и разобрав хвост.

    Прежняя пара остаётся неизменной. После сбоя подготовленную новую пару
    восстанавливает штатный импорт с теми же новым курсором и историей.
    """
    начало = time.perf_counter_ns()
    чтение._требовать(str(uuid.UUID(задача)) == задача, "неканонический UUID")
    корень = модель._путь(корень_репозитория)
    исходник, старый_курсор, старое_назначение, новый_курсор, назначение = map(
        модель._путь, (источник, прежний_кэш, прежняя_история, кэш, история))
    чтение._требовать(старое_назначение.is_relative_to(корень) and
        назначение.is_relative_to(корень), "история вне своего checkout")
    for курсор in (старый_курсор, новый_курсор):
        чтение._требовать(not курсор.is_relative_to(корень) and not any(
            os.path.lexists(предок / ".git") for предок in курсор.parents),
            "курсор должен быть вне Git")
    явные = (исходник, старый_курсор, старое_назначение, новый_курсор, назначение)
    замки = tuple(модель._путь(str(курсор) + ".lock") for курсор in (
        старый_курсор, новый_курсор))
    чтение._требовать(len(set((*явные, *замки))) == 7,
        "совпадающие пути данных и замков")
    чтение._требовать(all(путь.parent.is_dir() for путь in (
        старый_курсор, старое_назначение, новый_курсор, назначение)),
        "родительский каталог отсутствует")

    with ExitStack() as стек:
        if not без_записи:
            for курсор in sorted((старый_курсор, новый_курсор)):
                стек.enter_context(чтение._замок(курсор))
        чтение._требовать(not новый_курсор.exists() and not назначение.exists(),
            "новая история или курсор уже существуют; используйте обычный импорт")
        _, _, прежняя, _ = прочитать_подтверждённую_историю(
            задача, старый_курсор, старое_назначение)
        профиль = {"прочитано_байтов": 0, "разобрано_строк": 0}
        начало_чтения = time.perf_counter_ns()
        with os.fdopen(os.open(исходник, os.O_RDONLY | os.O_NOFOLLOW), "rb") as поток:
            состояние = os.fstat(поток.fileno())
            чтение._обычный(состояние)
            данные = модель._приём(поток, задача, прежняя, состояние.st_size, профиль)
            _сверить_последнее_наблюдение(поток, прежняя)
            дописано, перепроверено = чтение._сверить_снимок(
                поток, исходник, состояние, данные)
            профиль["прочитано_байтов"] += перепроверено
        профиль["чтение_наносекунды"] = time.perf_counter_ns() - начало_чтения
        байты = чтение._байты(данные)
        новое = {"история": данные, "метка": чтение._метка(состояние),
            "назначение": str(назначение), "реализация": модель._РЕАЛИЗАЦИЯ,
            "подготовлено": False, "ожидаемый_sha256": None}
        начало_записи = time.perf_counter_ns()
        if not без_записи:
            подготовленное = {**новое, "подготовлено": True}
            чтение._установить(новый_курсор, чтение._байты({"данные": подготовленное,
                "sha256": чтение._хэш(чтение._байты(подготовленное))}))
            чтение._установить(назначение, байты)
            чтение._установить(новый_курсор, чтение._байты({"данные": новое,
                "sha256": чтение._хэш(чтение._байты(новое))}))
        профиль["сохранение_наносекунды"] = time.perf_counter_ns() - начало_записи
        профиль["всего_наносекунды"] = time.perf_counter_ns() - начало
        return {"схема": "fum.перенос-истории-модели.1", "задача": задача,
            "новых_наблюдений": данные["число_наблюдений"] - прежняя["число_наблюдений"],
            "число_наблюдений": данные["число_наблюдений"], "событий": len(данные["события"]),
            "пропусков": len(данные["пропуски"]), "последнее": данные["последнее"],
            "неполный_хвост": данные["неполный_хвост"], "дописано_после_снимка": дописано,
            "полнота": not данные["пропуски"] and not данные["неполный_хвост"] and not дописано,
            "история_sha256": чтение._хэш(байты), "изменения_нужны": True,
            "без_записи": без_записи, "профиль": профиль}

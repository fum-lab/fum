"use strict";

// Единственный API текущего issued request; повтор/история не создают новое чтение.
async function передать_полный_ответ(среда, параметры) {
    let стадия = "вход", ключ = null, сеанс = null, подтверждение = null;
    let вызовов = 0, порций = 0;
    const отказ = () => ({схема:"fum.мост-полного-ответа.1",состояние:"не принят",стадия,
        вызовов_читающего_адаптера:вызовов,порций,сеанс,подтверждение,допуск_эффекта:false});
    const размер_строки = текст => {let размер=0;for(const знак of текст){const код=знак.codePointAt(0);размер+=код<128?1:код<2048?2:код<65536?3:4;}return размер;};
    const кавычки = текст => "'" + текст.split("'").join("'\\''") + "'";
    const ИДЕНТИФИКАТОР = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
    try {
        const допустимые = ["корень","контейнер","запрос","лимит_аргумента"];
        if (!параметры || Object.keys(параметры).some(имя=>!допустимые.includes(имя))) return отказ();
        const {корень,контейнер,запрос,лимит_аргумента=262144} = параметры;
        if (![корень,контейнер].every(путь=>typeof путь==="string"&&путь.startsWith("/")&&!/[\x00-\x1f]/.test(путь)) ||
            !Number.isInteger(лимит_аргумента)||лимит_аргумента<512||лимит_аргумента>262144 ||
            !запрос||запрос.схема!=="fum.запрос-внешнего-чтения.1"||!ИДЕНТИФИКАТОР.test(запрос.цикл)||
            Object.keys(запрос).sort().join(",")!=="параметры,схема,цикл") return отказ();
        const чтение = запрос.параметры, цикл = запрос.цикл, задача = чтение?.threadId;
        if (!ИДЕНТИФИКАТОР.test(задача)||typeof чтение.hostId!=="string"||!чтение.hostId||чтение.turnLimit!==1||
            чтение.includeOutputs!==true||!Number.isInteger(чтение.maxOutputCharsPerItem)||
            чтение.maxOutputCharsPerItem<1||чтение.maxOutputCharsPerItem>16000||
            Object.keys(чтение).some(имя=>!["threadId","hostId","turnLimit","includeOutputs","maxOutputCharsPerItem","cursor"].includes(имя))||
            ("cursor" in чтение && typeof чтение.cursor!=="string")) return отказ();
        const инструменты = среда.инструменты;
        if (![среда.хэш,среда.сохранить,среда.загрузить,среда.принять_описание,
            инструменты?.exec_command,инструменты?.write_stdin,инструменты?.mcp__codex_app__read_thread].every(э=>typeof э==="function")) return отказ();
        ключ="fum.мост-полного-ответа.1:"+цикл+":"+задача;
        const контекст=JSON.stringify({корень,контейнер,лимит_аргумента,схема:запрос.схема,цикл,
            чтение:[задача,чтение.hostId,чтение.turnLimit,чтение.includeOutputs,
                чтение.maxOutputCharsPerItem,"cursor" in чтение?чтение.cursor:null]});
        const прежняя=среда.загрузить(ключ);
        if(прежняя) {
            if(прежняя.контекст!==контекст) return {...отказ(),стадия:"Прежний контекст не совпадает"};
            return прежняя.итог ? {...прежняя.итог,повтор:true} : {...отказ(),стадия:"Прежний неизвестный исход запрещает повтор"};
        }
        среда.сохранить(ключ,{состояние:"намерение",запрос,контекст});
        стадия="готовность приёмника";
        const файл=контейнер+"/чтение-"+цикл+".json";
        const аргументы=["python3","-B",корень+"/Инструменты/fum-svyaznostj-rabochej-sessii/scripts/приём_полного_ответа_узла.py",
            "--корень-контейнера",контейнер,"--цикл",цикл,"--задача",задача,"--запрос",JSON.stringify(чтение)];
        let результат=await инструменты.exec_command({cmd:аргументы.map(кавычки).join(" "),workdir:корень,tty:true,yield_time_ms:1000,max_output_tokens:1000});
        if(!Number.isInteger(результат.session_id)||результат.exit_code!==undefined) throw Error("Приёмник не ожидает поток");
        сеанс=результат.session_id;
        const готовность=JSON.parse(результат.output);
        if(JSON.stringify(готовность)!==JSON.stringify({схема:"fum.готовность-приёма-ответа.1",цикл,задача,файл})) {
            // Порядок ключей JSON не имеет значения.
            if(готовность.схема!=="fum.готовность-приёма-ответа.1"||готовность.цикл!==цикл||готовность.задача!==задача||готовность.файл!==файл||Object.keys(готовность).length!==4) throw Error("Чужая готовность");
        }
        стадия="один текущий API";
        вызовов++;
        const ответ=await инструменты.mcp__codex_app__read_thread(чтение);
        if(!ответ||typeof ответ!=="object") throw Error("Нет полного ответа API");
        const сырые=JSON.stringify(ответ);
        const отпечаток=среда.хэш(сырые);
        if(!Number.isInteger(отпечаток.байты)||отпечаток.байты<1||отпечаток.байты>67108864||!/^[0-9a-f]{64}$/.test(отпечаток.sha256)) throw Error("Недопустимый отпечаток");
        среда.сохранить(ключ,{состояние:"передача",запрос,контекст,сеанс,отпечаток,сырой_ответ:сырые});
        const заголовок={схема:"fum.передача-полного-ответа.1",цикл,задача,запрос:чтение,...отпечаток};
        const конец={схема:"fum.конец-полного-ответа.1",цикл,задача,...отпечаток};
        const кадр=JSON.stringify(заголовок)+"\n"+сырые+"\n"+JSON.stringify(конец)+"\n";
        let позиция=0,вывод="";
        стадия="ограниченная передача stdin";
        while(позиция<кадр.length) {
            let низ=1,верх=Math.min(100000,кадр.length-позиция),число=0;
            while(низ<=верх) {
                const середина=Math.floor((низ+верх)/2);
                const проба={session_id:сеанс,chars:кадр.slice(позиция,позиция+середина),yield_time_ms:1000,max_output_tokens:1000};
                if(размер_строки(JSON.stringify(проба))<=лимит_аргумента){число=середина;низ=середина+1;}else верх=середина-1;
            }
            const последний=кадр.charCodeAt(позиция+число-1),следующий=кадр.charCodeAt(позиция+число);
            if(последний>=0xd800&&последний<=0xdbff&&следующий>=0xdc00&&следующий<=0xdfff) число--;
            if(число<1) throw Error("Порция не помещается в предел инструмента");
            const порция={session_id:сеанс,chars:кадр.slice(позиция,позиция+число),yield_time_ms:1000,max_output_tokens:1000};
            if(размер_строки(JSON.stringify(порция))>лимит_аргумента) throw Error("Порция превышает предел инструмента");
            результат=await инструменты.write_stdin(порция);порций++;позиция+=число;
            вывод+=результат.output||"";
            if(вывод.length>16384||результат.exit_code!==undefined&&(результат.exit_code!==0||позиция!==кадр.length)) throw Error("Приёмник завершился до конца");
            if(результат.exit_code===undefined&&результат.session_id!==сеанс) throw Error("Неизвестный исход порции");
        }
        стадия="точный долговечный ACK";
        for(let попытка=0;результат.exit_code===undefined&&попытка<12;попытка++) {
            результат=await инструменты.write_stdin({session_id:сеанс,chars:"",yield_time_ms:1000,max_output_tokens:1000});
            вывод+=результат.output||"";
            if(вывод.length>16384) throw Error("Слишком большой ACK");
        }
        if(результат.exit_code!==0) throw Error("Исход приёмника не подтверждён");
        подтверждение=JSON.parse(вывод);
        const ожидаемое={схема:"fum.ACK-полного-ответа.1",цикл,задача,файл,...отпечаток};
        if(Object.keys(подтверждение).length!==6||Object.keys(ожидаемое).some(имя=>подтверждение[имя]!==ожидаемое[имя])) throw Error("Чужой ACK");
        среда.сохранить(ключ,{состояние:"ACK подтверждён, доставка не подтверждена",запрос,контекст,сеанс,подтверждение});
        стадия="штатное описание контейнеру";
        await среда.принять_описание({цикл,задача,файл});
        const итог={схема:"fum.мост-полного-ответа.1",состояние:"полный ответ сохранён",вызовов_читающего_адаптера:вызовов,порций,подтверждение,
            описание:{цикл,задача,файл},доставка_описания:"не подтверждена",допуск_эффекта:false};
        среда.сохранить(ключ,{состояние:"полный ответ сохранён",запрос,контекст,итог});
        return итог;
    } catch(ошибка) {
        if(ключ) {const прежняя=среда.загрузить(ключ)||{};среда.сохранить(ключ,{...прежняя,состояние:"неизвестный исход",стадия,сеанс,подтверждение:подтверждение||прежняя.подтверждение});}
        return отказ();
    }
}
if (typeof module !== "undefined") module.exports = {передать_полный_ответ};

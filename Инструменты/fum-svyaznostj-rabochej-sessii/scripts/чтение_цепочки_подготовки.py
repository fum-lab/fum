def требовать(условие, пояснение):
    if not условие:
        raise ValueError(пояснение)


def _проверить_срок(крайний_срок):
    требовать(time.monotonic() <= крайний_срок, 'исчерпан предел времени чтения цепочки')


def _хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def _шаблон(значение, выражение):
    return type(значение) is str and re.fullmatch(выражение, значение) is not None


def _формат_хэша(значение):
    return _шаблон(значение, '[0-9a-f]{64}')


def _оид(значение):
    return _шаблон(значение, '[0-9a-f]{40}')


def _разобрать(сырые):
    def пары(записи):
        итог = {}
        for ключ, значение in записи:
            требовать(ключ not in итог, 'повторный JSON-ключ')
            итог[ключ] = значение
        return итог

    def константа(значение):
        raise ValueError('недопустимая JSON-константа: ' + значение)

    return json.loads(сырые.decode('utf-8'), object_pairs_hook=пары, parse_constant=константа)


def _путь(значение, крайний_срок, кэш_имён=None):
    _проверить_срок(крайний_срок)
    требовать(type(значение) is str or isinstance(значение, Path), 'неверный тип пути')
    путь = Path(значение)
    требовать(путь.is_absolute() and str(путь) == os.fspath(значение)
               and путь.resolve() == путь, 'нужен физический абсолютный путь')
    for часть in (путь, *путь.parents):
        _проверить_срок(крайний_срок)
        if часть == часть.parent:
            continue
        искомое = часть.name.casefold()
        # Кэш живёт ровно один публичный вызов. Метаданные родителя читаются заново;
        # resolve/is_symlink и FD/байты никогда не пропускаются.
        метка = _метка(часть.parent.lstat())
        ключ = (часть.parent, искомое)
        прежняя = None if кэш_имён is None else кэш_имён.get(ключ)
        if прежняя is not None and прежняя[0] == метка:
            совпадения = прежняя[1]
        else:
            with os.scandir(часть.parent) as записи:
                совпадения = [запись.name for запись in записи if запись.name.casefold() == искомое]
            if кэш_имён is not None and len(кэш_имён) < 4096:
                кэш_имён[ключ] = (метка, совпадения)
        требовать(совпадения in ([], [часть.name]), 'неоднозначный регистр пути')
        требовать(not часть.is_symlink(), 'символический компонент пути')
    return путь


def _цель_указателя(база, значение, крайний_срок, кэш_имён):
    """Разрешает штатный относительный gitdir, проверяя каждый компонент до '..'."""
    исходный = Path(значение)
    текущий = Path(исходный.anchor) if исходный.is_absolute() else база
    for часть in исходный.parts:
        if часть in (исходный.anchor, '.'):
            continue
        текущий = текущий.parent if часть == '..' else текущий / часть
        _путь(текущий, крайний_срок, кэш_имён)
    return текущий


def _метка(свойства):
    return (свойства.st_dev, свойства.st_ino, свойства.st_mode, свойства.st_uid,
            свойства.st_nlink, свойства.st_size, свойства.st_mtime_ns, свойства.st_ctime_ns)


def _каталог(путь, крайний_срок, кэш_имён=None):
    путь = _путь(путь, крайний_срок, кэш_имён)
    свойства = путь.stat()
    требовать(stat.S_ISDIR(свойства.st_mode), 'нужен обычный каталог')
    return (свойства.st_dev, свойства.st_ino, свойства.st_mode, свойства.st_uid)


def _прочитать(путь, крайний_срок, кэш_имён=None):
    путь = _путь(путь, крайний_срок, кэш_имён)
    if not os.path.lexists(путь):
        return None
    до = путь.lstat()
    требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1
               and до.st_uid == os.geteuid() and до.st_size <= 128 * 1024 * 1024, 'необычный, чужой или слишком большой файл')
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(дескриптор, 'rb') as файл:
        требовать(_метка(os.fstat(файл.fileno())) == _метка(до), 'файл заменён перед чтением')
        части, прочитано = [], 0
        while True:
            _проверить_срок(крайний_срок)
            часть = файл.read(1024 * 1024)
            if not часть:
                break
            части.append(часть)
            прочитано += len(часть)
            требовать(прочитано <= до.st_size, 'файл вырос при чтении')
        требовать(_метка(os.fstat(файл.fileno())) == _метка(до), 'файл изменён при чтении')
    _проверить_срок(крайний_срок)
    требовать(_путь(путь, крайний_срок, кэш_имён) == путь
        and _метка(путь.lstat()) == _метка(до), 'файл заменён после чтения')
    return (_метка(до), b''.join(части))


def относительный_путь(значение):
    требовать(type(значение) is str and значение and значение == PurePosixPath(значение).as_posix()
        and not PurePosixPath(значение).is_absolute() and not значение.startswith('-')
        and '\\' not in значение and not any(часть.casefold() in {'.', '..', '.git'}
            for часть in значение.split('/')) and all(ord(часть) >= 32 and ord(часть) != 127 for часть in значение),
        'небезопасный относительный путь зависимости')
    return значение


def регистрация_индекса(данные, *, полный=False):
    """Файловое чтение полного SHA1 index v2/v3; Git из late guard не вызывается."""
    требовать(len(данные) >= 32 and данные[:4] == b'DIRC'
        and hashlib.sha1(данные[:-20]).digest() == данные[-20:], 'повреждённый индекс регистрации')
    версия, число = struct.unpack('>II', данные[4:12])
    требовать(версия in (2, 3), 'RO контракт требует полный SHA1 index v2/v3')
    позиция, записи = 12, {}
    for _ in range(число):
        начало = позиция
        требовать(позиция + 62 <= len(данные) - 20, 'обрезанный индекс')
        режим = struct.unpack('>I', данные[позиция + 24:позиция + 28])[0]
        объект = данные[позиция + 40:позиция + 60].hex()
        флаги = struct.unpack('>H', данные[позиция + 60:позиция + 62])[0]
        требовать(not флаги & 0xB000, 'конфликтующий или скрывающий индекс')
        позиция += 62
        if флаги & 0x4000:
            требовать(версия == 3 and данные[позиция:позиция + 2] == bytes(2), 'расширенный индекс скрывает состояние')
            позиция += 2
        конец = данные.find(bytes(1), позиция, len(данные) - 20)
        требовать(конец >= позиция, 'нет имени индексного пути')
        имя = os.fsdecode(данные[позиция:конец])
        относительный_путь(имя)
        требовать(имя and имя not in записи, 'повторный или пустой индексный путь')
        записи[имя] = (режим, объект)
        позиция = начало + ((конец + 1 - начало + 7) // 8) * 8
        требовать(позиция <= len(данные) - 20 and not any(данные[конец:позиция])
            and (флаги & 0xFFF == 0xFFF or флаги & 0xFFF == конец - (начало + 62 + (2 if флаги & 0x4000 else 0))),
            'неверная длина имени или выравнивание индекса')
    while позиция < len(данные) - 20:
        требовать(позиция + 8 <= len(данные) - 20, 'обрезанное расширение индекса')
        имя = данные[позиция:позиция + 4]
        длина = struct.unpack('>I', данные[позиция + 4:позиция + 8])[0]
        требовать(имя[:1].isupper() and имя not in (b'LINK', b'SDIR'), 'разделённый или неизвестный обязательный индекс')
        позиция += 8 + длина
    требовать(позиция == len(данные) - 20, 'неверная длина индекса')
    return записи if полный else {п: з for п, з in записи.items() if з[0] == 0o160000 or п == '.gitmodules'}


def _гитлинки(снимок, корень, собственный, общий):
    требовать(type(снимок) is dict and set(снимок) == _ПОЛЯ_СНИМКА
        and снимок['схема'] == 'fum.снимок-окружения-зависимостей.1', 'форма снимка')
    требовать((снимок['корень'], снимок['гит_каталог'], снимок['общий_гит_каталог'])
        == (str(корень), str(собственный), str(общий)), 'чужая топология')
    ссылка = снимок['ссылка']
    требовать(type(ссылка) is str and (ссылка.startswith('refs/heads/codex/')
        or ссылка in {'refs/heads/fuma', 'refs/heads/planirovaniye'})
        and _оид(снимок['коммит']), 'неверный исторический ref/OID')
    требовать(all(_формат_хэша(снимок[поле]) for поле in ('индекс', 'конфигурация'))
        and all(снимок[поле] is None or _формат_хэша(снимок[поле])
            for поле in ('описание_подмодулей', 'конфигурация_дерева')), 'неверный SHA снимка')
    код = снимок['код']
    требовать(type(код) is dict and set(код) == {'подготовка_зависимостей.py',
        'proveritj-git-zavisimostj.py'} and all(_формат_хэша(значение)
        for значение in код.values()), 'неверный исторический отпечаток кода')
    текст, записи, итог = снимок['инвентарь_индекса'], {}, {}
    требовать(type(текст) is str and (not текст or текст.endswith('\0')), 'неполный stage0')
    for строка in текст.split('\0')[:-1] if текст else []:
        мета, разделитель, путь = строка.partition('\t')
        запись = re.fullmatch(r'H (100644|100755|120000|160000) ([0-9a-f]{40}) 0', мета)
        требовать(разделитель and запись and путь not in записи, 'повреждённый stage0')
        относительный_путь(путь)
        записи[путь] = (int(запись[1], 8), запись[2])
        if запись[1] == '160000':
            итог[путь] = запись[2]
    требовать(not итог or (записи.get('.gitmodules', (None,))[0] == 0o100644
        and _формат_хэша(снимок['описание_подмодулей'])), 'gitlinks без регистрации')
    return итог


def _события(данные, пути):
    требовать(type(данные['готова']) is bool and данные['готова']
        and type(данные['группа_процессов']) is int
        and данные['группа_процессов'] > 0, 'незавершённая квитанция')
    требовать(type(данные['состояния']) is dict
        and данные['состояния'] == {путь: 'готова' for путь in пути}
        and type(данные['события']) is list, 'неполный результат')
    состояния, шаги, группы = {путь: 'не_начата' for путь in пути}, {}, {}
    for событие in данные['события']:
        требовать(type(событие) is dict and type(событие.get('путь')) is str
            and событие['путь'] in пути and type(событие.get('фаза')) is str, 'чужое событие')
        путь, фаза = событие['путь'], событие['фаза']
        прежнее = состояния[путь]
        if фаза == 'намерение' or фаза in _ФАЗЫ:
            требовать(set(событие) == {'путь', 'фаза', 'группа_процессов'}
                and type(событие['группа_процессов']) is int
                and событие['группа_процессов'] > 0, 'неверная группа события')
            if фаза == 'намерение':
                требовать(прежнее == 'не_начата', 'повторное намерение')
                шаги[путь], группы[путь] = -1, событие['группа_процессов']
            else:
                номер = _ФАЗЫ.index(фаза)
                требовать(прежнее == 'выполняется'
                    and событие['группа_процессов'] == группы.get(путь)
                    and (номер == шаги.get(путь, -2) + 1
                        or шаги.get(путь) == 0 and номер == 2), 'порядок эффектов')
                шаги[путь] = номер
            состояния[путь] = 'выполняется'
        elif фаза == 'отказ':
            требовать(set(событие) == {'путь', 'фаза', 'причина'}
                and type(событие['причина']) is str and прежнее == 'выполняется', 'неверный отказ')
            состояния[путь] = 'не_завершена'
        elif фаза == 'готовность_проверена':
            требовать(set(событие) == {'путь', 'фаза'} and прежнее == 'выполняется'
                and шаги.get(путь) == len(_ФАЗЫ) - 1, 'незавершённый эффект')
            состояния[путь] = 'готова'
        elif фаза == 'автономное_подтверждение':
            требовать(set(событие) == {'путь', 'фаза', 'прежнее_состояние', 'прежний_исход_неизвестен'}
                and событие['прежнее_состояние'] == прежнее
                and type(событие['прежний_исход_неизвестен']) is bool
                and событие['прежний_исход_неизвестен'] == (прежнее in {'выполняется', 'не_завершена'}),
                'неверное автономное подтверждение')
            состояния[путь] = 'готова'
        else:
            raise ValueError('неизвестная фаза события')
    требовать(состояния == данные['состояния'], 'история и результат расходятся')


ФактыЧтенияЗависимости = namedtuple('ФактыЧтенияЗависимости',
    'корень гит_каталог путь секция ревизия форк оригинал формы_гит')


class ДопускЧтенияЦепочки:
    __slots__ = ('__ключ', '__файлы', '__каталоги', '__индекс', '__регистрация', '__формы', '__вне_гит', '__зависимости', '__указатели', '__weakref__')

    def __new__(класс, *, ключ=None):
        требовать(класс is ДопускЧтенияЦепочки and ключ is _КЛЮЧ_ФАБРИКИ,
            'допуск создаёт только фабрика первичного чтения')
        return object.__new__(класс)

    def __setattr__(сам, имя, значение):
        raise ValueError('допуск неизменяем')

    def __reduce_ex__(сам, протокол):
        raise ValueError('допуск нельзя переносить между процессами')

    @property
    def формы_гит(сам):
        _проверить_допуск(сам)
        return сам.__формы


def _проверить_допуск(допуск):
    требовать(type(допуск) is ДопускЧтенияЦепочки
        and getattr(допуск, '_ДопускЧтенияЦепочки__ключ', None) is _КЛЮЧ_ФАБРИКИ
        and допуск in _ВЫДАННЫЕ_ДОПУСКИ, 'нужен подлинный допуск текущего процесса')


def _выдать_допуск(файлы, каталоги, индекс, регистрация, формы, вне_гит, зависимости, указатели):
    допуск = ДопускЧтенияЦепочки(ключ=_КЛЮЧ_ФАБРИКИ)
    значения = (_КЛЮЧ_ФАБРИКИ, tuple(файлы), tuple(каталоги), индекс,
        tuple(регистрация), tuple(формы), tuple(вне_гит), tuple(зависимости), tuple(указатели))
    for имя, значение in zip(('ключ', 'файлы', 'каталоги', 'индекс', 'регистрация', 'формы', 'вне_гит', 'зависимости', 'указатели'), значения):
        object.__setattr__(допуск, '_ДопускЧтенияЦепочки__' + имя, значение)
    _ВЫДАННЫЕ_ДОПУСКИ.add(допуск)
    return допуск


def получить_факты_зависимостей(допуск):
    """Проверенные immutable roots/stock forms; готовность доказывает leaf validator K."""
    _проверить_допуск(допуск)
    сверить_чтение_цепочки(допуск)
    return допуск._ДопускЧтенияЦепочки__зависимости


def профиль_запоминания_индекса(допуск):
    """Свежие скаляры; счётчики относятся к процессу, вес — к удерживаемому memo."""
    _проверить_допуск(допуск)
    with _ЗАМОК_ЗАПОМИНАНИЯ:
        запись = _ЗАПОМНЕННЫЕ_ИНДЕКСЫ.get(допуск)
        веса = [з.вес for з in _ЗАПОМНЕННЫЕ_ИНДЕКСЫ.values()]
        return {**_СЧЁТЧИКИ_ЗАПОМИНАНИЯ,
            'удержано_байтов': 0 if запись is None else запись.вес,
            'всего_удержано_байтов': sum(веса) + (_СЛУЖЕБНЫЙ_РЕЗЕРВ if веса else 0),
            'записей': len(веса)}


def _проекция_позднего_индекса(допуск, сырые):
    with _ЗАМОК_ЗАПОМИНАНИЯ:
        запись = _ЗАПОМНЕННЫЕ_ИНДЕКСЫ.get(допуск)
        if запись is not None and сырые == запись.байты:
            _СЧЁТЧИКИ_ЗАПОМИНАНИЯ['попадания'] += 1
            return запись.проекция, None
        _СЧЁТЧИКИ_ЗАПОМИНАНИЯ['промахи'] += 1
    разобранная = регистрация_индекса(сырые)
    # Независимые глубоко неизменяемые значения, без view исходного словаря.
    проекция = tuple(sorted((путь, (режим, объект))
        for путь, (режим, объект) in разобранная.items()))
    return проекция, (сырые, проекция)


def _сохранить_поздний_индекс(допуск, кандидат, крайний_срок):
    if кандидат is None:
        return
    сырые, проекция = кандидат
    вес = sys.getsizeof(сырые) + sys.getsizeof(проекция) + 1024
    for пара in проекция:
        вес += sys.getsizeof(пара) + sys.getsizeof(пара[0]) + sys.getsizeof(пара[1])
        вес += sum(sys.getsizeof(значение) for значение in пара[1])
    запись = _ЗапомненныйИндекс(сырые, проекция, вес)
    with _ЗАМОК_ЗАПОМИНАНИЯ:
        остальные = [з.вес for ключ, з in _ЗАПОМНЕННЫЕ_ИНДЕКСЫ.items() if ключ is not допуск]
        помещается = (вес <= _ПРЕДЕЛ_ЗАПИСИ_ИНДЕКСА
            and len(остальные) < _ПРЕДЕЛ_ЧИСЛА_ИНДЕКСОВ
            and _СЛУЖЕБНЫЙ_РЕЗЕРВ + sum(остальные) + вес <= _ПРЕДЕЛ_ЗАПОМИНАНИЯ_ИНДЕКСОВ)
        _проверить_срок(крайний_срок)
        # Успешный MISS заменяет только собственную последнюю запись.
        # Нехватка памяти возвращает прежний полный разбор без запоминания.
        _ЗАПОМНЕННЫЕ_ИНДЕКСЫ.pop(допуск, None)
        if помещается:
            _ЗАПОМНЕННЫЕ_ИНДЕКСЫ[допуск] = запись


def допустить_чтение_цепочки(выбор, *, корень, исходный_коммит, ветка,
                            исполнитель, корневая_задача, гит):
    крайний_срок = time.monotonic() + _ПРЕДЕЛ_ВРЕМЕНИ
    кэш_имён = {}
    корень = _путь(корень, крайний_срок, кэш_имён)
    требовать(_оид(исходный_коммит), 'нужен полный SHA-1 исходного W')
    требовать(type(ветка) is str and ветка.startswith('refs/heads/'), 'неверный текущий ref')
    for значение in (исполнитель, корневая_задача):
        требовать(type(значение) is str and str(uuid.UUID(значение)) == значение, 'нужен UUID')
    требовать(os.environ.get('CODEX_THREAD_ID') == исполнитель, 'чужой native UUID')
    файлы, каталоги, формы, приватные_пути = {}, {}, set(), set()

    def каталог(путь, *, приватный=False):
        путь = _путь(путь, крайний_срок, кэш_имён)
        метка = _каталог(путь, крайний_срок, кэш_имён)
        if приватный:
            требовать(stat.S_IMODE(метка[2]) == 0o700
                and метка[3] == os.geteuid(), 'небезопасный приватный каталог')
        требовать(путь not in каталоги or каталоги[путь] == метка, 'дрейф каталога')
        каталоги[путь] = метка

    def файл(путь, *, режим=None, обязателен=True, вне_гит=False):
        путь = _путь(путь, крайний_срок, кэш_имён)
        if вне_гит:
            требовать(not any(os.path.lexists(предок / '.git') for предок in путь.parents),
                'приватный материал должен находиться вне Git')
            каталог(путь.parent, приватный=True)
            приватные_пути.add(путь)
        for папка in путь.parents:
            каталог(папка)
        снимок = _прочитать(путь, крайний_срок, кэш_имён)
        требовать(снимок is not None or not обязателен, 'отсутствует выбранный файл')
        if снимок is not None and режим is not None:
            требовать(stat.S_IMODE(снимок[0][2]) == режим, 'неверный режим файла')
        требовать(путь not in файлы or файлы[путь] == снимок, 'дрейф выбранного файла')
        файлы[путь] = снимок
        return None if снимок is None else снимок[1]

    def чтение(*хвост):
        _проверить_срок(крайний_срок)
        формы.add(tuple(хвост))
        сырые = гит(корень, *хвост)
        _проверить_срок(крайний_срок)
        требовать(type(сырые) is bytes, 'Git callback должен вернуть bytes')
        return сырые

    требовать(type(выбор) is dict and set(выбор) == {'путь', 'sha256'}
        and _формат_хэша(выбор['sha256']), 'неверный независимый selector')
    сырые = файл(выбор['путь'], режим=0o600, вне_гит=True)
    требовать(_хэш(сырые) == выбор['sha256'], 'подменён selector')
    описание_выбора = _разобрать(сырые)
    требовать(type(описание_выбора) is dict and set(описание_выбора) == {'схема', 'корень', 'коммит',
        'исполнитель', 'координатор', 'описание_sha256', 'зависимости', 'квитанция_sha256', 'квитанция_путь'}
        and описание_выбора['схема'] == 'fum.выбор-чтения-зависимостей.2'
        and (описание_выбора['корень'], описание_выбора['коммит'], описание_выбора['исполнитель'],
            описание_выбора['координатор']) == (str(корень), исходный_коммит, исполнитель, корневая_задача)
        and _формат_хэша(описание_выбора['описание_sha256'])
        and _формат_хэша(описание_выбора['квитанция_sha256'])
        and _шаблон(описание_выбора['квитанция_путь'], _ПУТЬ_ПОКОЛЕНИЯ), 'чужой descriptor D.4')
    требовать(чтение('rev-parse', '--show-toplevel').decode().strip() == str(корень), 'чужой Git-корень')
    собственный = _путь(чтение('rev-parse', '--absolute-git-dir').decode().strip(), крайний_срок, кэш_имён)
    общий = _путь(чтение('rev-parse', '--path-format=absolute', '--git-common-dir').decode().strip(), крайний_срок, кэш_имён)
    требовать(собственный != общий, 'нужен собственный linked worktree')
    требовать(чтение('symbolic-ref', '-q', 'HEAD').decode().strip() == ветка, 'чужой текущий ref')
    владельцы = [блок.splitlines()[0].removeprefix('worktree ') for блок in
        чтение('worktree', 'list', '--porcelain').decode().split('\n\n')
        if 'branch ' + ветка in блок.splitlines()]
    требовать(владельцы == [str(корень)], 'неоднозначный владелец ref')
    for путь in (корень / '.git', собственный / 'gitdir', собственный / 'commondir'):
        файл(путь)
    указатель = файлы[корень / '.git'][1].decode().splitlines()
    требовать(len(указатель) == 1 and указатель[0].startswith('gitdir: ')
        and (корень / указатель[0][8:]).resolve() == собственный, 'перенаправлен .git')
    требовать((собственный / файлы[собственный / 'gitdir'][1].decode().strip()).resolve()
        == корень / '.git', 'чужой обратный gitdir')
    требовать((собственный / файлы[собственный / 'commondir'][1].decode().strip()).resolve()
        == общий, 'чужой commondir')
    файл(общий / 'config')
    файл(собственный / 'config.worktree', обязателен=False)
    ожидаемые, секции = {}, set()
    требовать(type(описание_выбора['зависимости']) is list and описание_выбора['зависимости'], 'пустой состав')
    for запись in описание_выбора['зависимости']:
        требовать(type(запись) is dict and set(запись) == {'путь', 'секция', 'ревизия', 'форк', 'оригинал'},
            'неверная запись зависимости')
        путь, секция = относительный_путь(запись['путь']), относительный_путь(запись['секция'])
        требовать(путь not in ожидаемые and секция not in секции and _оид(запись['ревизия'])
            and all(type(запись[поле]) is str and запись[поле] for поле in ('форк', 'оригинал')), 'неверный pin/URL')
        ожидаемые[путь], секции = запись['ревизия'], секции | {секция}
    for имена in (list(ожидаемые), list(секции)):
        требовать(len({имя.casefold() for имя in имена}) == len(имена)
            and not any(левое.casefold().startswith(правое.casefold() + '/') for левое in имена
                for правое in имена if левое != правое), 'пересекающиеся пути')
    описание = файл(корень / '.gitmodules')
    требовать(_хэш(описание) == описание_выбора['описание_sha256']
        and чтение('show', исходный_коммит + ':.gitmodules') == описание, 'регистрация не равна основе')
    индекс = собственный / 'index'
    снимок_индекса = _прочитать(индекс, крайний_срок, кэш_имён)
    требовать(снимок_индекса is not None, 'нет полного индекса')
    регистрация = регистрация_индекса(снимок_индекса[1])
    объект_описания = hashlib.sha1(b'blob ' + str(len(описание)).encode() + b'\0' + описание).hexdigest()
    требовать(регистрация == {'.gitmodules': (0o100644, объект_описания),
        **{путь: (0o160000, объект) for путь, объект in ожидаемые.items()}}, 'дрейф stage0 регистрации')
    базовая = {}
    for запись in чтение('ls-tree', '-r', '-z', исходный_коммит).split(b'\0'):
        if not запись:
            continue
        мета, имя = запись.split(b'\t', 1)
        режим, тип, объект = мета.decode().split()
        имя = относительный_путь(os.fsdecode(имя))
        if режим == '160000' or имя == '.gitmodules':
            требовать(имя not in базовая and _оид(объект)
                and тип == ('commit' if режим == '160000' else 'blob'), 'неверная базовая регистрация')
            базовая[имя] = (int(режим, 8), объект)
    требовать(базовая == регистрация, 'основа не равна stage0 регистрации')

    факты_зависимостей, указатели_зависимостей = [], []
    for запись in описание_выбора['зависимости']:
        рабочий = _путь(корень / запись['путь'], крайний_срок, кэш_имён)
        админ = _путь(собственный / 'modules' / запись['секция'], крайний_срок, кэш_имён)
        каталог(рабочий)
        каталог(админ)
        указатель = файл(рабочий / '.git').decode('utf-8').splitlines()
        требовать(len(указатель) == 1 and указатель[0].startswith('gitdir: ')
            and указатель[0][8:]
            and _цель_указателя(рабочий, указатель[0][8:], крайний_срок, кэш_имён) == админ,
            'перенаправлен Git-каталог зависимости')
        указатели_зависимостей.append((рабочий, указатель[0][8:], админ))
        индекс_листа = файл(админ / 'index')
        требовать(not any(режим == 0o160000 for режим, объект in
            регистрация_индекса(индекс_листа, полный=True).values()), 'вложенный gitlink не получает допуск листа')
        файл(админ / 'config')
        файл(админ / 'config.worktree', обязателен=False)
        требовать(файл(админ / 'commondir', обязателен=False) is None,
            'зависимость не должна перенаправлять общий Git-каталог')
        формы_зависимости = (('rev-parse', 'HEAD'), ('rev-parse', '--show-toplevel'),
            ('status', '--porcelain', '--untracked-files=all', '--ignore-submodules=none'),
            ('rev-parse', '--verify', 'HEAD'), ('ls-tree', '-r', '-z', запись['ревизия']))
        факты_зависимостей.append(ФактыЧтенияЗависимости(str(рабочий), str(админ),
            *(запись[поле] for поле in ('путь', 'секция', 'ревизия', 'форк', 'оригинал')),
            формы_зависимости))

    def загрузить(путь, хэш):
        сырые = файл(путь, режим=0o600)
        требовать(_хэш(сырые) == хэш, 'подменена квитанция цепочки')
        данные = _разобрать(сырые)
        требовать(type(данные) is dict, 'квитанция должна быть объектом')
        return данные, сырые

    def архив(хэш):
        каталог(собственный / _АРХИВ, приватный=True)
        return собственный / _АРХИВ / (хэш + '.json')

    каталог(собственный / _КАТАЛОГ_ПОКОЛЕНИЙ, приватный=True)
    данные, сырые = загрузить(собственный / описание_выбора['квитанция_путь'], описание_выбора['квитанция_sha256'])
    требовать(данные.get('схема') == 'fum.подготовка-зависимостей.4'
        and данные.get('поколение') == Path(описание_выбора['квитанция_путь']).stem, 'выбрана другая D.4')
    узлы, просмотренные = [], set()
    while True:
        _проверить_срок(крайний_срок)
        хэш = _хэш(сырые)
        требовать(хэш not in просмотренные, 'повтор SHA или цикл цепочки')
        просмотренные.add(хэш)
        требовать(type(данные) is dict and type(данные.get('схема')) is str
            and данные['схема'] in _ВЕРСИИ, 'неизвестная схема квитанции')
        версия = int(данные['схема'].rsplit('.', 1)[1])
        поля = _ПОЛЯ | ({'предыдущая_квитанция'} if версия >= 2 else set())
        поля |= {'набор_графов'} if версия >= 3 else set()
        поля |= {'поколение'} if версия == 4 else set()
        требовать(set(данные) == поля and данные['исполнитель'] == исполнитель
            and данные['корневая_задача'] == корневая_задача, 'чужая форма/идентичность')
        ссылки = _гитлинки(данные['снимок'], корень, собственный, общий)
        _события(данные, set(ссылки))
        набор = данные.get('набор_графов')
        if версия == 3 or набор is not None:
            требовать(type(набор) is dict and set(набор) == {'путь', 'хэш_байтов'}
                and _формат_хэша(набор['хэш_байтов']), 'неверный selector набора')
            байты = файл(набор['путь'], режим=0o600, вне_гит=True)
            требовать(_хэш(байты) == набор['хэш_байтов'], 'подменён исторический набор')
            содержимое = _разобрать(байты)
            требовать(type(содержимое) is dict and set(содержимое) == {'схема', 'графы'}
                and содержимое['схема'] == 'fum.набор-графов-зависимостей.1'
                and type(содержимое['графы']) is dict and not содержимое['графы'],
                'непустой вложенный граф не поддержан leaf consumer')
        предок = данные.get('предыдущая_квитанция')
        if версия == 4:
            требовать(type(предок) is dict and set(предок) == {'поколение', 'sha256'}
                and _формат_хэша(предок['sha256'])
                and (предок['поколение'] is None or _формат_хэша(предок['поколение']))
                and _формат_хэша(данные['поколение']), 'неверная ссылка D.4')
            основание = {ключ: данные[ключ] for ключ in ('снимок', 'исполнитель',
                'корневая_задача', 'предыдущая_квитанция', 'набор_графов')}
            канон = (json.dumps(основание, ensure_ascii=False, sort_keys=True,
                separators=(',', ':')) + '\n').encode('utf-8')
            требовать(_хэш(канон) == данные['поколение'], 'подменён ID поколения')
            требовать(len(данные['события']) == len(ссылки)
                and {событие['путь'] for событие in данные['события']} == set(ссылки)
                and all(событие['фаза'] == 'автономное_подтверждение'
                    and событие['прежнее_состояние'] == 'не_начата'
                    and событие['прежний_исход_неизвестен'] is False
                    for событие in данные['события']), 'D.4 содержит иной переход')
        elif версия >= 2 and not (версия == 3 and предок is None):
            требовать(type(предок) is dict and set(предок) == {'sha256'}
                and _формат_хэша(предок['sha256']), 'неверная legacy-ссылка')
        узлы.append((данные, ссылки))
        if версия == 1 or версия == 3 and предок is None:
            break
        прежние, прежние_сырые = загрузить(архив(предок['sha256']), предок['sha256'])
        требовать(версия == 4 or прежние.get('схема') != 'fum.подготовка-зависимостей.4',
            'legacy-ребро не принимает новое поколение')
        if версия == 4:
            поколение = предок['поколение']
            источник = собственный / (_СТАРОЕ_ИМЯ if поколение is None else
                _КАТАЛОГ_ПОКОЛЕНИЙ + '/' + поколение + '.json')
            оригинал, исходные_байты = загрузить(источник, предок['sha256'])
            требовать(исходные_байты == прежние_сырые, 'оригинал и архив расходятся')
            требовать((type(оригинал.get('схема')) is str and оригинал['схема'] in _ВЕРСИИ - {'fum.подготовка-зависимостей.4'})
                if поколение is None else оригинал.get('схема') == 'fum.подготовка-зависимостей.4'
                    and оригинал.get('поколение') == поколение, 'подменено исходное поколение')
        данные, сырые = прежние, прежние_сырые
    активная, активные_ссылки = узлы[0]
    требовать(активная['снимок']['ссылка'] == ветка and активные_ссылки == ожидаемые
        and активная['снимок']['описание_подмодулей'] == описание_выбора['описание_sha256'],
        'D.4 не подтверждает выбранную регистрацию')
    for данные, ссылки in узлы:
        требовать(чтение('merge-base', '--is-ancestor', данные['снимок']['коммит'], исходный_коммит) == b'',
            'исторический снимок не является предком C')
    for (новые, новые_ссылки), (старые, старые_ссылки) in zip(узлы, узлы[1:]):
        новый, старый = новые['снимок'], старые['снимок']
        if новые['схема'] == 'fum.подготовка-зависимостей.4':
            требовать(новый['ссылка'] != старый['ссылка'] and новые_ссылки == старые_ссылки
                and all(новый[поле] == старый[поле] for поле in
                    ('описание_подмодулей', 'конфигурация', 'конфигурация_дерева')), 'неверное ребро D.4')
            требовать(чтение('merge-base', '--is-ancestor', старый['коммит'], новый['коммит']) == b'',
                'подменён предок D.4')
        else:
            требовать(новый['ссылка'] == старый['ссылка'], 'смена ref через legacy')
        требовать(all(новые_ссылки.get(путь) == объект for путь, объект in старые_ссылки.items())
            and all(событие['фаза'] == 'автономное_подтверждение' for событие in новые['события']
                if событие['путь'] in старые_ссылки), 'утрачен gitlink или запрет init')
    допуск = _выдать_допуск(файлы.items(), каталоги.items(), индекс,
        sorted(регистрация.items()), sorted(формы), приватные_пути, факты_зависимостей, указатели_зависимостей)
    кандидат, срок_сверки = _сверить_чтение_цепочки(допуск)
    _проверить_срок(крайний_срок)
    _сохранить_поздний_индекс(допуск, кандидат, min(крайний_срок, срок_сверки))
    return допуск


def сверить_чтение_цепочки(допуск):
    кандидат, крайний_срок = _сверить_чтение_цепочки(допуск)
    _сохранить_поздний_индекс(допуск, кандидат, крайний_срок)


def _сверить_чтение_цепочки(допуск):
    _проверить_допуск(допуск)
    крайний_срок = time.monotonic() + _ПРЕДЕЛ_ВРЕМЕНИ
    кэш_имён = {}
    for база, текст, ожидаемая in допуск._ДопускЧтенияЦепочки__указатели:
        требовать(_цель_указателя(база, текст, крайний_срок, кэш_имён) == ожидаемая,
            'изменена физическая цель указателя зависимости')
    for путь in допуск._ДопускЧтенияЦепочки__вне_гит:
        требовать(not any(os.path.lexists(предок / '.git') for предок in путь.parents),
            'приватный вход цепочки оказался внутри Git')
    for путь, метка in допуск._ДопускЧтенияЦепочки__каталоги:
        требовать(_каталог(путь, крайний_срок, кэш_имён) == метка, 'изменена identity каталога цепочки')
    for путь, снимок in допуск._ДопускЧтенияЦепочки__файлы:
        требовать(_прочитать(путь, крайний_срок, кэш_имён) == снимок, 'изменены bytes/identity цепочки')
    индекс = _прочитать(допуск._ДопускЧтенияЦепочки__индекс, крайний_срок, кэш_имён)
    требовать(индекс is not None, 'нет полного индекса регистрации')
    проекция, кандидат = _проекция_позднего_индекса(допуск, индекс[1])
    требовать(проекция == допуск._ДопускЧтенияЦепочки__регистрация,
        'изменена регистрационная проекция индекса')
    _проверить_срок(крайний_срок)
    return кандидат, крайний_срок

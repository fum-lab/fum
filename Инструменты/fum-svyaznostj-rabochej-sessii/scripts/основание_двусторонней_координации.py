"""Читающая привязка человеческого основания к конечному обычному поручению.

Метки ФС и штатный кэш предполагают одного кооперативного писателя. Смысл
оригиналов и поздних уточнений выбирает ROOT; эвристик по словам здесь нет.
"""
import hashlib
import os
from pathlib import Path
import uuid

import сообщения_задачи as читатель
import обработка_сообщений as обработка
import граница_выбранных_команд as границы
import типизированная_контрольная_точка as адреса
import обычное_поручение as обычное

ОГРАНИЧЕНИЯ = ('Обычные результаты и препятствия направляются только ROOT в пределах поручения '
    'без повторного разрешения человека. Это основание не разрешает публикацию, интеграцию, '
    'расширение поручения, завершение задачи или автоматическое продолжение.')


def требовать(условие, причина):
    if not условие: raise ValueError(причина)


def поля(данные, ожидаемые):
    требовать(type(данные) is dict and set(данные)==set(ожидаемые), 'неверные поля основания координации')


def хэш(сырые):
    return hashlib.sha256(сырые).hexdigest()


def проверить(корень, решение, вход):
    корень=адреса.точный_абсолютный(корень)
    смысл=решение['координация']
    поля(смысл, {'экземпляры','начало_корня','контекст','решение','хэш_поручения',
        'адресат','сообщения','получение','ограничения'})
    идентификатор_корня=решение['координатор']
    требовать(type(идентификатор_корня) is str and str(uuid.UUID(идентификатор_корня))==идентификатор_корня, 'неверный ROOT')
    требовать(смысл['адресат']==идентификатор_корня and смысл['сообщения']==['результат','препятствие']
        and смысл['получение']=='подтверждение требуется' and смысл['ограничения']==ОГРАНИЧЕНИЯ,
        'адресат или эффекты выходят из конечной координации')
    требовать(смысл['хэш_поручения']==хэш(решение['поручение'].encode()), 'подменено конечное поручение')
    акт=решение['акт']
    требовать(type(акт['область']) is list and акт['область'] and all(type(п) is str and п for п in акт['область'])
        and type(акт['ветка']) is str and акт['ветка'].startswith('refs/heads/codex/'), 'нет конечной области')
    обычное._гит(корень,'check-ref-format',акт['ветка'])
    обычное.проверить_область(корень,акт['область'],
        [имя+'проверка-покрытия' if имя.endswith('/') else имя for имя in акт['область']])
    семантика=смысл['решение']; поля(семантика, {'актуальность','поздние','основание','область','рассмотренные_неоднозначности'})
    требовать(семантика['актуальность'] in {'актуально','уточнено'}
        and type(семантика['основание']) is str and семантика['основание'].strip()
        and семантика['область']==акт['область'], 'актуальность или суженная область не подтверждены ROOT')
    основания=смысл['экземпляры']; поздние=семантика['поздние']
    требовать(type(основания) is list and основания and len(set(основания))==len(основания)
        and type(поздние) is list and len(set(поздние))==len(поздние)
        and not set(основания).intersection(поздние), 'повторные или пустые экземпляры основания')
    for э in [*основания,*поздние]: обработка.отпечаток(э)
    требовать(семантика['актуальность']!='уточнено' or поздние, 'уточнение требует позднего человеческого основания')
    обработка.проверить_контекст(смысл['контекст'])
    частный=вход['основание_координации']; поля(частный, {'источник','оригиналы'})
    номер=частный['источник']
    требовать(type(номер) is int and 0<=номер<len(вход['источники']), 'нет независимого ROOT источника')
    источник=вход['источники'][номер]
    требовать(источник['задача']==идентификатор_корня, 'чужой ROOT источника')
    файл=адреса.точный_абсолютный(источник['путь']); кэш=адреса.точный_абсолютный(источник['кэш'],приватный=True)
    данные=читатель._кэш_прочитать(кэш, идентификатор_корня)
    состояние=файл.stat(); читатель._обычный(состояние)
    требовать(данные is not None and данные['реализация']==читатель._РЕАЛИЗАЦИЯ
        and данные['метка']==читатель._метка(состояние) and данные['граница']==состояние.st_size
        and данные['граница']==источник['граница_снимка']['граница']
        and данные['sha256']==источник['граница_снимка']['sha256'],
        'неподготовленный или устаревший кэш; скрытый полный разбор запрещён')
    снимок=читатель.прочитать_сообщения(файл, идентификатор_корня, корень_репозитория=корень, кэш=кэш, без_записи=True)
    границы.проверить_снимок(снимок, источник['граница_снимка'], требовать)
    требовать(снимок['профиль']['режим']=='неизменная метка ФС'
        and снимок['профиль']['прочитано_байтов']==снимок['профиль']['разобрано_строк']==0,
        'неожиданный повторный разбор ROOT')
    требовать(смысл['контекст']==обработка.контекст_снимка(снимок), 'непроверенный или неполный поздний контекст')
    неоднозначные=[э for э in снимок['сообщения'] if э['происхождение']!='человек']
    требовать(семантика['рассмотренные_неоднозначности']==[э['экземпляр'] for э in неоднозначные],
        'неоднозначный контекст не рассмотрен адресно ROOT')
    if неоднозначные:
        требовать(семантика['актуальность']=='уточнено' and поздние,
            'неоднозначность требует позднего человеческого уточнения и решения ROOT')
        последняя_позиция=max(э['позиция']['начало'] for э in снимок['сообщения'] if э['экземпляр'] in поздние)
        требовать(all(э['позиция']['начало']<последняя_позиция for э in неоднозначные),
            'поздний неоднозначный ввод требует отдельного решения')
    поля(смысл['начало_корня'], {'sha256','thread_source'})
    требовать(смысл['начало_корня']['thread_source']=='user', 'ROOT не является человеческим чатом')
    with os.fdopen(os.open(файл,os.O_RDONLY|os.O_NOFOLLOW),'rb') as поток:
        первый=поток.readline(1024*1024)
        требовать(первый.endswith(b'\n') and хэш(первый)==смысл['начало_корня']['sha256']==снимок['источник'], 'подменено начало ROOT')
        начало=читатель._разобрать(первый)
        требовать(начало.get('type')=='session_meta' and начало.get('payload',{}).get('id')==идентификатор_корня
            and начало['payload'].get('thread_source')=='user', 'агентский или неизвестный ROOT')
        выбранные=[]
        for э in основания:
            выбранные.append(обработка.сверить_экземпляры({'экземпляр':э,'контекст':смысл['контекст'],'поздние':поздние},снимок))
        все=set(основания+поздние)
        исходные=[э for э in снимок['сообщения'] if э['экземпляр'] in все]
        требовать([э['экземпляр'] for э in выбранные]==[э['экземпляр'] for э in исходные if э['экземпляр'] in основания],
            'изменён исходный порядок оснований')
        сырые_ссылки=частный['оригиналы']
        требовать(type(сырые_ссылки) is list and len(сырые_ссылки)==len(исходные), 'нет всех RAW оснований и уточнений')
        оригиналы=[]
        for запись,э in zip(сырые_ссылки,исходные):
            поля(запись, {'экземпляр','путь','sha256'})
            требовать(запись['экземпляр']==э['экземпляр'] and э['происхождение']=='человек', 'RAW не является выбранным человеком')
            файл_оригинала=адреса.точный_абсолютный(запись['путь'],приватный=True)
            with os.fdopen(os.open(файл_оригинала,os.O_RDONLY|os.O_NOFOLLOW),'rb') as поток_оригинала:
                с=os.fstat(поток_оригинала.fileno());читатель._обычный(с,приватный=True)
                требовать(с.st_nlink==1 and с.st_size<=16*1024*1024, 'RAW превышает предел или имеет hardlink')
                сырые=поток_оригинала.read(16*1024*1024+1)
                после=os.fstat(поток_оригинала.fileno())
                требовать(len(сырые)==с.st_size and читатель._метка(после)==читатель._метка(с)
                    and читатель._метка(файл_оригинала.stat())==читатель._метка(с), 'RAW изменился при чтении')
            позиция=э['позиция']
            поток.seek(позиция['начало']);оригинал=поток.read(позиция['конец']-позиция['начало'])
            требовать(сырые==оригинал and хэш(сырые)==запись['sha256']==позиция['sha256'], 'RAW не совпадает с исходным диапазоном ROOT')
            требовать(э['экземпляр']==хэш(читатель._байты({'задача':идентификатор_корня,'источник':снимок['источник'],**позиция})),
                'кэш подменил идентичность экземпляра')
            сырой=читатель._разобрать(сырые)
            требовать(сырой.get('type')=='response_item' and type(сырой.get('payload')) is dict
                and сырой['payload']==э['сырой_объект']
                and сырой['payload'].get('type')=='message' and сырой['payload'].get('role')=='user'
                and читатель._КЛАССИФИКАТОР.классифицировать_сообщение(сырой['payload'])=='человек',
                'RAW не подтверждает сохранённое человеческое происхождение')
            содержимое=сырой['payload']['content']
            требовать(содержимое==э['содержимое'], 'кэш подменил оригинал')
            требовать(type(содержимое) is list and содержимое and all(type(ч) is dict and set(ч)=={'type','text'}
                and ч['type']=='input_text' and type(ч['text']) is str for ч in содержимое), 'неподдержанный оригинал человеческого основания')
            оригиналы.append({'экземпляр':э['экземпляр'],'позиция':позиция,'текст':''.join(ч['text'] for ч in содержимое)})
    требовать(читатель._метка(файл.stat())==данные['метка'], 'ROOT изменился при сверке RAW')
    return {'схема':'fum.основание-двусторонней-координации.1','координатор':идентификатор_корня,
        'начало_корня':смысл['начало_корня'],'контекст':смысл['контекст'],'решение':семантика,
        'хэш_поручения':смысл['хэш_поручения'],'ветка':акт['ветка'],'область':акт['область'],
        'оригиналы':оригиналы,'сообщения':смысл['сообщения'],'получение':смысл['получение'],'ограничения':ОГРАНИЧЕНИЯ}


def блок(данные):
    """Один детерминированный блок для запуска и буквальной native-сверки."""
    строки=['\nОснование двусторонней координации:', 'ROOT: '+данные['координатор'],
        'Контекст SHA-256: '+данные['контекст']['sha256'], 'Граница: '+str(данные['контекст']['граница']),
        'Поручение SHA-256: '+данные['хэш_поручения'], 'Ветка: '+данные['ветка'],
        'Область: '+читатель._байты(данные['область']).decode(),
        'Решение ROOT: '+читатель._байты(данные['решение']).decode()]
    for оригинал in данные['оригиналы']:
        строки.extend(['Оригинал: '+оригинал['экземпляр'], 'Диапазон RAW: '+читатель._байты(оригинал['позиция']).decode(),
            'Начало дословного текста:',оригинал['текст'],'Конец дословного текста.'])
    строки.extend([ОГРАНИЧЕНИЯ,'Подтверждение получения требуется: сообщи ROOT проверенные SHA и диапазоны, сохраняй оригиналы и ограничения в собственной паре Журнала.'])
    return '\n'.join(строки)+'\n'

import Foundation
import CryptoKit

// Чистая синтетическая модель: не читает источник, не пишет Git и не даёт полномочий.
struct СобытиеПамяти: Equatable {
    enum Вид: String { case входящее, переход }
    let вид: Вид
    let сессия: String
    let получатель: String
    let источник: String
    let идентификатор: String
    let позиция: UInt64
    let предыдущее: String?
    let происхождение: String
    let байты: Data
    var хэш: String { SHA256.hash(data: байты).map { String(format: "%02x", $0) }.joined() }
}
struct ЗаписьПамяти: Equatable {
    let событие: СобытиеПамяти
    let хэш: String
    let родитель: String
    let коммит: String
}
enum РешениеПамяти: Equatable { case подготовить(String), записано(String), удержать }
private func допустимыйOID(_ значение: String) -> Bool {
    (значение.utf8.count == 40 || значение.utf8.count == 64) &&
    значение.utf8.allSatisfy { ($0 >= 48 && $0 <= 57) || ($0 >= 97 && $0 <= 102) }
}
struct МодельПамяти {
    enum Фаза { case готово, намерение, неизвестно, публикацияНеизвестна }
    let сессия: String
    let получатель: String
    let источник: String
    private(set) var последняяПозиция: UInt64 = 0
    private(set) var последнееСобытие: String?
    private(set) var вершина: String
    private(set) var записи: [String: ЗаписьПамяти] = [:]
    private(set) var фаза: Фаза = .готово
    private(set) var ожидаемое: СобытиеПамяти?
    init(сессия: String, получатель: String, источник: String, основа: String) {
        self.сессия = сессия; self.получатель = получатель; self.источник = источник; self.вершина = основа
    }
    mutating func начать(_ событие: СобытиеПамяти, единственныйПисатель: Bool) -> РешениеПамяти {
        guard единственныйПисатель, фаза == .готово, допустимыйOID(вершина),
              событие.сессия == сессия, событие.получатель == получатель, событие.источник == источник,
              !событие.идентификатор.isEmpty, !событие.происхождение.isEmpty else { return .удержать }
        if let запись = записи[событие.идентификатор] {
            return запись.событие == событие && запись.хэш == событие.хэш ? .записано(запись.коммит) : .удержать
        }
        guard последняяПозиция < UInt64.max, событие.позиция == последняяПозиция + 1,
              событие.предыдущее == последнееСобытие else { return .удержать }
        ожидаемое = событие; фаза = .намерение
        return .подготовить(событие.хэш)
    }
    mutating func завершить(коммит: String, родитель: String) -> Bool {
        guard фаза == .намерение, let событие = ожидаемое, допустимыйOID(коммит), коммит != родитель, родитель == вершина else { return false }
        записи[событие.идентификатор] = ЗаписьПамяти(событие: событие, хэш: событие.хэш, родитель: родитель, коммит: коммит)
        вершина = коммит; последнееСобытие = событие.идентификатор; последняяПозиция = событие.позиция
        ожидаемое = nil; фаза = .готово; return true
    }
    mutating func неизвестныйКоммит() { if фаза == .намерение { фаза = .неизвестно } }
    // Восстанавливается только найденная точная запись; отсутствие не разрешает повтор эффекта.
    mutating func восстановить(_ запись: ЗаписьПамяти) -> Bool {
        guard фаза == .неизвестно, let событие = ожидаемое, запись.событие == событие,
              запись.хэш == событие.хэш, запись.родитель == вершина, допустимыйOID(запись.коммит), запись.коммит != запись.родитель else { return false }
        фаза = .намерение
        return завершить(коммит: запись.коммит, родитель: запись.родитель)
    }
    mutating func публикацияНеизвестна() { if фаза == .готово { фаза = .публикацияНеизвестна } }
    mutating func подтвердитьПубликацию(удалённыйOID: String) -> Bool {
        guard фаза == .публикацияНеизвестна, удалённыйOID == вершина else { return false }
        фаза = .готово; return true
    }
}

import Foundation
import Darwin
func проверить(_ условие: @autoclosure () -> Bool, _ имя: String) {
    if !условие() { let д = Data(("ОТКАЗ " + имя + "\n").utf8); _ = д.withUnsafeBytes { Darwin.write(STDERR_FILENO, $0.baseAddress, $0.count) }; Darwin._exit(1) }
}
let основа = String(repeating: "a", count: 40), первыйOID = String(repeating: "b", count: 40)
let второйOID = String(repeating: "c", count: 40)
func событие(_ id: String, _ номер: UInt64, _ предыдущий: String?, _ текст: String,
             _ вид: СобытиеПамяти.Вид = .входящее) -> СобытиеПамяти {
    СобытиеПамяти(вид: вид, сессия: "session", получатель: "recipient", источник: "synthetic",
                  идентификатор: id, позиция: номер, предыдущее: предыдущий,
                  происхождение: "synthetic", байты: Data(текст.utf8))
}
let первое = событие("event-1", 1, nil, "одинаковый текст")
let второе = событие("event-2", 2, "event-1", "одинаковый текст")
var модель = МодельПамяти(сессия: "session", получатель: "recipient", источник: "synthetic", основа: основа)
проверить(модель.начать(первое, единственныйПисатель: false) == .удержать, "конкурент")
проверить(модель.начать(второе, единственныйПисатель: true) == .удержать, "пропуск")
проверить(модель.начать(первое, единственныйПисатель: true) == .подготовить(первое.хэш), "намерение")
проверить(модель.начать(первое, единственныйПисатель: true) == .удержать, "повтор намерения")
проверить(!модель.завершить(коммит: первыйOID, родитель: второйOID), "чужой родитель")
проверить(!модель.завершить(коммит: основа, родитель: основа), "коммит без продвижения")
модель.неизвестныйКоммит()
проверить(модель.начать(первое, единственныйПисатель: true) == .удержать, "авария и повтор")
let чужая = ЗаписьПамяти(событие: первое, хэш: String(repeating: "0", count: 64), родитель: основа, коммит: первыйOID)
проверить(!модель.восстановить(чужая), "неверное свидетельство")
let точная = ЗаписьПамяти(событие: первое, хэш: первое.хэш, родитель: основа, коммит: первыйOID)
проверить(модель.восстановить(точная), "точное восстановление")
проверить(модель.начать(первое, единственныйПисатель: true) == .записано(первыйOID), "доставка дважды")
проверить(модель.начать(событие("event-1", 1, nil, "другой текст"), единственныйПисатель: true) == .удержать, "конфликт ID")
проверить(модель.начать(второе, единственныйПисатель: true) == .подготовить(второе.хэш), "одинаковые тексты")
проверить(модель.завершить(коммит: второйOID, родитель: первыйOID), "второй коммит")
модель.публикацияНеизвестна()
let третье = событие("event-3", 3, "event-2", "переход", .переход)
проверить(модель.начать(третье, единственныйПисатель: true) == .удержать, "неизвестная доставка")
проверить(!модель.подтвердитьПубликацию(удалённыйOID: первыйOID), "чужой OID")
проверить(модель.подтвердитьПубликацию(удалённыйOID: второйOID), "подтверждённая доставка")
проверить(модель.начать(третье, единственныйПисатель: true) == .подготовить(третье.хэш), "отдельный переход")
print("ПРОЙДЕНО синтетическая модель; источники и Git не подключены")

def байты(данные):
    return (json.dumps(данные, ensure_ascii=False, sort_keys=True, allow_nan=False) + "\n").encode()


def хэш(сырые):
    return hashlib.sha256(сырые).hexdigest()


def сохранить(путь, данные):
    with Path(путь).open("xb") as файл:
        файл.write(данные)
    Path(путь).chmod(0o600)


class Наблюдатель:
    """Возвращает исходный Popen, не вызывает poll/wait/communicate дополнительно."""
    def __init__(сам, путь=None):
        сам.вызовы_гит, сам.процессы, сам.интервалы, сам.стек = [], [], [], []
        сам.путь = путь

    @contextlib.contextmanager
    def интервал(сам, имя):
        запись = {"номер": len(сам.интервалы), "имя": имя,
                  "родитель": сам.стек[-1] if сам.стек else None, "исключение": None}
        сам.интервалы.append(запись)
        сам.стек.append(запись["номер"])
        начало = time.perf_counter_ns()
        try:
            yield
        except BaseException as ошибка:
            запись["исключение"] = type(ошибка).__name__
            raise
        finally:
            запись["нс"] = time.perf_counter_ns() - начало
            сам.стек.pop()

    def __enter__(сам):
        сам.настоящий = subprocess.Popen

        def создать(*аргументы, **параметры):
            команда = параметры.get("args", аргументы[0] if аргументы else None)
            if not isinstance(команда, (list, tuple)) or not команда or Path(os.fsdecode(команда[0])).name != "git":
                return сам.настоящий(*аргументы, **параметры)
            запись = {"номер": len(сам.вызовы_гит), "argv": [os.fsdecode(элемент) for элемент in команда],
                "cwd": os.fsdecode(параметры.get("cwd") or os.getcwd()),
                "интервал": сам.стек[-1] if сам.стек else None, "исключение": None,
                "начало_нс": time.perf_counter_ns(), "процесс_python": os.getpid()}
            сам.вызовы_гит.append(запись)
            try:
                процесс = сам.настоящий(*аргументы, **параметры)
            except BaseException as ошибка:
                запись.update(исключение=type(ошибка).__name__, код=None)
                raise
            сам.процессы.append((запись, процесс))
            return процесс

        subprocess.Popen = создать
        return сам

    def __exit__(сам, *исход):
        subprocess.Popen = сам.настоящий
        for запись, процесс in сам.процессы:
            запись["код"] = процесс.returncode
        if сам.путь is not None:
            try:
                сохранить(сам.путь, байты({"вызовы_гит": сам.вызовы_гит, "интервалы": сам.интервалы,
                    "исключение": исход[0].__name__ if исход[0] else None}))
            except OSError:
                if исход[0] is None:
                    raise
                # Ошибка диагностики не подменяет исходное исключение опыта.

    def обернуть(сам, объект, имя, метка):
        исходная = getattr(объект, имя)

        def вызов(*аргументы, **параметры):
            with сам.интервал(метка):
                return исходная(*аргументы, **параметры)

        setattr(объект, имя, вызов)
        return исходная


def гит(корень, *аргументы):
    return subprocess.run(["git", "-C", str(корень), *аргументы],
                          capture_output=True, check=True).stdout


def ветка(корень, имя):
    return {"ветка": "refs/heads/" + имя,
            "коммит": гит(корень, "rev-parse", имя).decode().strip(),
            "дерево": гит(корень, "rev-parse", имя + "^{tree}").decode().strip()}


def подключить(код):
    sys.path.insert(0, str(код / КАТАЛОГ / "scripts"))
    return importlib.import_module("копия_кода_обратного_приёма")


def исходники(код):
    return {путь: хэш((код / путь).read_bytes()) for путь in ПУТИ}


def псевдонимы_из_копии(код):
    """Известный exec_module без регистрации в sys.modules проверяется отдельно."""
    владелец = sys.modules.get("сообщения_задачи")
    if владелец is None:
        return {}
    модуль = владелец._КЛАССИФИКАТОР
    относительный = "Инструменты/fum-snimki-indeksa/scripts/происхождение_сообщений.py"
    ожидаемый = код / относительный
    путь = Path(модуль.__file__).resolve()
    assert путь == ожидаемый, "Незарегистрированный псевдоним вне выбранной копии"
    функция = модуль.классифицировать_сообщение
    assert Path(функция.__code__.co_filename).resolve() == ожидаемый, "Функция псевдонима вне выбранной копии"
    assert Path(модуль.__spec__.origin).resolve() == ожидаемый, "Источник псевдонима вне выбранной копии"
    return {"сообщения_задачи._КЛАССИФИКАТОР": {"путь": относительный,
        "sha256": хэш(путь.read_bytes()), "файл_функции": относительный}}


def код_из_копии(код):
    """Проверить зарегистрированные модули и известный незарегистрированный alias."""
    for модуль in tuple(sys.modules.values()):
        файл = getattr(модуль, "__file__", None)
        if файл and "Инструменты" in Path(файл).parts:
            путь = Path(файл).resolve()
            if not путь.is_relative_to(код) or путь.relative_to(код).as_posix() not in ПУТИ:
                raise AssertionError("Проектный импорт вне выбранной копии: " + str(путь))
    псевдонимы_из_копии(код)
    return исходники(код)



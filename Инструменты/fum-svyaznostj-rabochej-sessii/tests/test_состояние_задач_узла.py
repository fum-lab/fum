class ПамятьКонтейнера:
    """Явная локальная фикстура контракта, не API и не доказательство fsync."""
    def __init__(сам):
        сам.записи = {}
        сам.попытки = []
        сам.потерять_ответ = False

    def сохранить(сам, описание, данные):
        сам.попытки.append((copy.deepcopy(описание), данные))
        ключ = описание["идентификатор"]
        if ключ in сам.записи and сам.записи[ключ] != (описание, данные):
            raise ValueError("конфликт идентификатора")
        сам.записи[ключ] = (copy.deepcopy(описание), данные)
        if сам.потерять_ответ and описание["тип"] == "codex-read_thread":
            сам.потерять_ответ = False
            raise OSError("квитанция потеряна после записи")
        return {"описание": copy.deepcopy(описание), "размер": len(данные), "хэш": хэш(данные)}

    def перечень(сам):
        return {"схема": "fum.перечень-контейнера.1", "неполный_хвост": False,
            "записи": [{"описание": copy.deepcopy(описание), "размер": len(данные), "хэш": хэш(данные)}
                for описание, данные in сам.записи.values()]}

    def извлечь(сам, идентификатор):
        return сам.записи[идентификатор][1]


class ЦиклКонтроллера(ОжиданияУзла):
    def цикл(сам, *, история=None):
        модуль = importlib.import_module("состояние_задач_узла")
        if not hasattr(сам, "контейнер"):
            сам.контейнер = ПамятьКонтейнера()
        return модуль.ЦиклНаблюдения(сам.доверие, корень=сам.с.репо,
            контейнер=сам.контейнер, история=[] if история is None else история)

    def ответ(сам, задача=ДОЧЬ, *, статус="idle", ходы=None):
        объект = НативнаяПроекция().объект()
        внутренний = json.loads(объект["content"][0]["text"])
        внутренний["thread"].update(id=задача, cwd=str(сам.с.репо), status={"type": статус})
        внутренний["turns"] = [Сценарий.ход()] if ходы is None else ходы
        объект["content"][0]["text"] = json.dumps(внутренний, ensure_ascii=False)
        return объект

    def test_сырой_неизвестный_ответ_хранится_до_диагностики(сам):
        цикл = сам.цикл()
        объект = НативнаяПроекция().объект(("futureItem",))
        итог = цикл.наблюдать(lambda запрос: объект, источник="синтетическая фикстура")
        сам.assertEqual(len([описание for описание, _ in сам.контейнер.записи.values() if описание["тип"] == "codex-read_thread"]), 1)
        запись = итог["наблюдения"][0]
        сам.assertEqual(json.loads(сам.контейнер.извлечь(запись["объект"]["идентификатор"])), объект)
        сам.assertEqual(запись["состояние"], "ошибка разбора")
        сам.assertIn("неизвестный тип", запись["причина"])
        сам.assertEqual(итог["профиль"]["вызовов_читающего_адаптера"], 1)
        сам.assertEqual(итог["профиль"]["send"], 0)
        сам.assertEqual(итог["профиль"]["create"], 0)


class НативнаяПроекция(unittest.TestCase):
    def test_малый_файл_не_выделяет_память_по_полному_пределу(сам):
        модуль = importlib.import_module("состояние_задач_узла")
        with tempfile.TemporaryDirectory() as временный:
            файл = Path(временный).resolve() / "малый.json"; файл.write_bytes(b"{}")
            tracemalloc.start()
            try:
                сам.assertEqual(модуль.прочитать_файл(файл, предел=модуль.ПРЕДЕЛ), b"{}")
                _, пик = tracemalloc.get_traced_memory()
            finally: tracemalloc.stop()
            сам.assertLess(пик, 1024 * 1024)

    def test_файловый_ввод_отвергает_канал_ссылку_и_превышение(сам):
        модуль = importlib.import_module("состояние_задач_узла")
        with tempfile.TemporaryDirectory() as временный:
            каталог = Path(временный).resolve()
            канал = каталог / "канал"; os.mkfifo(канал)
            with сам.assertRaises(ValueError): модуль.прочитать_файл(канал, предел=10)
            файл = каталог / "ответ"; файл.write_bytes(b"01234567890")
            with сам.assertRaises(ValueError): модуль.прочитать_файл(файл, предел=10)
            ссылка = каталог / "ссылка"; ссылка.symlink_to(файл)
            with сам.assertRaises((ValueError, OSError)): модуль.прочитать_файл(ссылка, предел=20)
            сам.assertEqual(модуль.прочитать_файл(файл, предел=11), b"01234567890")


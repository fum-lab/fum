"""Настоящая подготовка, сохранение прежних свидетельств и закрытый отказ."""
import copy
import importlib
import json
import os
from pathlib import Path
import unittest
from unittest.mock import patch

import test_переподготовка_ожиданий_узла as основа

писатель = основа.писатель
смена = importlib.import_module('смена_незапечатанной_подготовки')


class СменаПодготовки(unittest.TestCase):
    def setUp(сам):
        сам.ф = основа.ПереподготовкаОжиданий()
        сам.ф.setUp()
        сам.addCleanup(сам.ф.doCleanups)
        исходная = писатель.коммит.подготовить
        def подготовить(*аргументы, **ключи):
            итог = исходная(*аргументы, **ключи)
            сам.дописать_модель()
            return итог
        with patch.object(писатель.коммит, 'подготовить', подготовить):
            with сам.assertRaisesRegex(ValueError, 'наблюдения модели изменились'):
                писатель.переподготовить(сам.ф.с.вход, сам.ф.ссылка)
        сам.п = copy.deepcopy(сам.ф.новые)
        for ключ in писатель.ВЫХОДЫ_ПОДГОТОВКИ:
            сам.п[ключ] = str(сам.ф.с.каталог / ('поколение2-' + ключ + '.json'))
        новые = сам.ф.с.ссылка_приватная('параметры-поколения2.json', сам.п)
        модель = писатель.коммит.наблюдать_модель(сам.ф.новые, без_записи=True)
        сам.запрос = {
            'схема': 'fum.смена-незапечатанной-подготовки.1',
            'хэш_входа': писатель.хэш(писатель.кодировать(сам.ф.с.вход)),
            'намерение_sha256': писатель.хэш(сам.ф.путь_намерения().read_bytes()),
            'прежние_параметры': сам.ф.ссылка, 'новые_параметры': новые,
            'основание_дрейфа': {'последнее': модель['последнее'],
                'число_наблюдений': модель['число_наблюдений']}}
        сам.сохранённые = сам.старые_свидетельства()

    def дописать_модель(сам):
        with сам.ф.с.о.нативный.open('ab') as поток:
            поток.write((json.dumps({'type': 'turn_context', 'timestamp': '2026-10-03T00:00:00Z',
                'payload': {'cwd': str(сам.ф.с.корень), 'model': 'gpt-6.1-sol', 'effort': 'ultra'}},
                ensure_ascii=False) + '\n').encode())

    def старые_свидетельства(сам):
        пути = [Path(сам.ф.с.вход['параметры']['путь']), Path(сам.ф.ссылка['путь']),
            *[Path(п[к]) for п in (сам.ф.с.о.параметры, сам.ф.новые)
                for к in ('сообщение', 'подготовка')],
            сам.ф.с.каталог / 'намерение.json']
        пути += list((сам.ф.с.каталог / 'переподготовка').glob('*'))
        return {str(п): (п.read_bytes(), п.stat().st_ino, п.stat().st_mtime_ns)
            for п in пути if п.is_file()}

    def выполнить(сам, запрос=None):
        return смена.сменить_подготовку(сам.ф.с.вход, запрос or сам.запрос)

    def отказ_без_подготовки(сам, запрос=None):
        до = сам.ф.снимок()
        with patch.object(писатель.коммит, 'подготовить', wraps=писатель.коммит.подготовить) as вызов:
            with сам.assertRaises((ValueError, OSError, KeyError)):
                сам.выполнить(запрос)
            сам.assertEqual(0, вызов.call_count)
        сам.assertEqual(до, сам.ф.снимок())

    def test_настоящий_дрейф_создаёт_поколение2_и_один_коммит(сам):
        with patch.object(писатель.коммит, 'подготовить', wraps=писатель.коммит.подготовить) as вызов:
            итог = сам.выполнить()
            сам.assertEqual(1, вызов.call_count)
        сам.assertEqual(2, итог['поколение'])
        сам.assertEqual(3, json.loads(Path(сам.п['подготовка']).read_bytes())['наблюдений'])
        сам.assertEqual(сам.сохранённые, сам.старые_свидетельства())
        сам.ф.сверить_сохранённое_основание()
        сам.ф.готовность(сам.п)
        итог = писатель.зафиксировать(сам.ф.с.вход, [основа.исходные.обычная.база.ЗАПУСК])
        сам.assertEqual(итог, писатель.повтор(сам.ф.с.вход))
        процесс = сам.ф.процесс('повтор')
        сам.assertEqual(0, процесс.returncode, процесс.stderr)
        сам.assertEqual(итог, json.loads(процесс.stdout))
        сам.assertEqual('1', сам.ф.с.ф.гит('rev-list', '--count', сам.ф.с.база+'..HEAD').strip())
        сам.assertEqual(сам.сохранённые, сам.старые_свидетельства())

    def test_неверное_основание_и_дрейф_не_вызывают_prepare(сам):
        for ключ in ('хэш_входа', 'намерение_sha256'):
            запрос = copy.deepcopy(сам.запрос); запрос[ключ] = '0' * 64
            with сам.subTest(поле=ключ): сам.отказ_без_подготовки(запрос)
        запрос = copy.deepcopy(сам.запрос)
        запрос['основание_дрейфа']['число_наблюдений'] += 1
        сам.отказ_без_подготовки(запрос)

    def test_partial_и_утраченный_маркер_не_меняют_поколение(сам):
        пути = [Path(сам.ф.новые['подготовка']),
            сам.ф.с.каталог / 'переподготовка/вызов-подготовки.json']
        for путь in пути:
            байты = путь.read_bytes(); путь.unlink()
            with сам.subTest(файл=путь.name): сам.отказ_без_подготовки()
            путь.write_bytes(байты); путь.chmod(0o600)

    def test_выходы_не_пересекают_первое_поколение(сам):
        п = copy.deepcopy(сам.п); п['сообщение'] = сам.ф.новые['сообщение']
        запрос = copy.deepcopy(сам.запрос)
        запрос['новые_параметры'] = сам.ф.с.ссылка_приватная('пересечение.json', п)
        сам.отказ_без_подготовки(запрос)

    def test_подмена_префикса_и_оборванный_хвост_отвергаются(сам):
        нативный = сам.ф.с.о.нативный; байты = нативный.read_bytes()
        for новые in (b' ' + байты[1:], байты + b'{"type":'):
            нативный.write_bytes(новые)
            with сам.subTest(размер=len(новые)): сам.отказ_без_подготовки()
        нативный.write_bytes(байты)

    def test_дрейф_идентичности_не_создаёт_поколение(сам):
        with patch.dict(os.environ, {'GIT_AUTHOR_EMAIL': 'other@example.invalid'}):
            сам.отказ_без_подготовки()

    def test_seal_квитанция_и_попытка_блокируют_смену(сам):
        seal = сам.ф.с.каталог / 'переподготовка/запечатано.json'
        квитанция = Path(сам.ф.новые['квитанция'])
        for путь in (seal, квитанция):
            путь.write_bytes(b'{}\n'); путь.chmod(0o600)
            with сам.subTest(файл=путь.name): сам.отказ_без_подготовки()
            путь.unlink()
        путь = сам.ф.путь_намерения(); намерение = json.loads(путь.read_bytes())
        намерение['стадия'] = 'попытка-коммита'
        писатель.сохранить(путь, намерение)
        запрос = copy.deepcopy(сам.запрос)
        запрос['намерение_sha256'] = писатель.хэш(путь.read_bytes())
        сам.отказ_без_подготовки(запрос)

    def test_перерыв_после_маркера_не_повторяет_prepare(сам):
        with patch.object(писатель.коммит, 'подготовить', side_effect=основа.Перерыв):
            with сам.assertRaises(основа.Перерыв): сам.выполнить()
        сам.отказ_без_подготовки()
        до = сам.ф.снимок()
        with patch.object(писатель.коммит, 'подготовить', wraps=писатель.коммит.подготовить) as вызов:
            with сам.assertRaisesRegex(ValueError, 'pending/unknown'):
                писатель.переподготовить(сам.ф.с.вход, сам.запрос['новые_параметры'])
            сам.assertEqual(0, вызов.call_count)
        сам.assertEqual(до, сам.ф.снимок())

    def test_запечатанное_поколение_и_изменённый_архив_отвергаются(сам):
        сам.выполнить()
        сам.отказ_без_подготовки()
        архив = сам.ф.с.каталог / 'переподготовка/поколения/2/предыдущее-поколение.json'
        архив.write_bytes(архив.read_bytes() + b'\n')
        with сам.assertRaises(ValueError):
            писатель.переподготовить(сам.ф.с.вход, сам.запрос['новые_параметры'])

    def test_печать_связывает_предшественника_даже_при_новом_хэше_ссылки(сам):
        сам.выполнить()
        путь = сам.ф.путь_намерения(); намерение = json.loads(путь.read_bytes())
        адрес = Path(намерение['переподготовка']['предыдущее']['путь'])
        сырые = адрес.read_bytes(); архив = json.loads(сырые)
        for данные in (сырые + b'\n', писатель.кодировать({**архив, 'запрос': {
                **архив['запрос'], 'основание_дрейфа': {
                    **архив['запрос']['основание_дрейфа'], 'число_наблюдений': 4}}})):
            адрес.write_bytes(данные)
            намерение['переподготовка']['предыдущее']['хэш'] = писатель.хэш(данные)
            писатель.сохранить(путь, намерение)
            with сам.subTest(байтов=len(данные)), сам.assertRaises(ValueError):
                писатель.действующий_вход(сам.ф.с.вход, намерение, новый_эффект=False)


if __name__ == '__main__':
    unittest.main()

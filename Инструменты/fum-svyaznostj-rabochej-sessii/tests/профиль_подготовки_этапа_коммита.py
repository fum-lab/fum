def содержит_абсолютный_путь(значение):
    if isinstance(значение,str): return os.path.isabs(значение)
    if isinstance(значение,list): return any(содержит_абсолютный_путь(э) for э in значение)
    if isinstance(значение,dict):
        return any(содержит_абсолютный_путь(к) or содержит_абсолютный_путь(в) for к,в in значение.items())
    return False



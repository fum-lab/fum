def файлы_замыкания(корень,*,селекторы=False):
    """Обход не зависит от ignore; Git не проходит сквозь symlink-каталоги."""
    найденные=set(); каталоги=[корень]
    while каталоги:
        каталог=каталоги.pop()
        with os.scandir(каталог) as записи:
            for запись in записи:
                if запись.name=='.git': continue
                if запись.is_dir(follow_symlinks=False): каталоги.append(Path(запись.path)); continue
                if селекторы and запись.name not in ('.gitignore','.gitattributes'): continue
                if запись.name=='.DS_Store': continue
                м.требовать(запись.is_file(follow_symlinks=False),'необычный файл замыкания')
                найденные.add(Path(запись.path))
    return найденные



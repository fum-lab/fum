        _, старые = м.история(корень, п['запрос'])
        запуск_обёртки = м.питон(обёртка, 'запустить', *общий, '--название', название, '--исполнитель', 'фасад',
            '--идентификатор-запуска', проверка['идентификатор'], '--класс-проверки', 'адресная')

def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--выход', required=True)
    разбор.add_argument('--раунды', type=int, default=3)
    разбор.add_argument('--контур', choices=('ordinary7','root5'), default='ordinary7')
    п = разбор.parse_args(); м.требовать(п.раунды in (1, 3), 'нужен один либо три парных раунда')
    выход = Path(п.выход)
    м.требовать(выход.is_absolute() and выход == выход.resolve() and not os.path.lexists(выход), 'нужен новый физический выход')
    выход.parent.mkdir(parents=True, exist_ok=True)
    приватный = Path(tempfile.mkdtemp(prefix='fum-fasad-profile-')).resolve(); приватный.chmod(0o700)
    данные = []; код = 0
    try:
        for сценарий in (('root5-fresh',) if п.контур=='root5' else ('fresh', 'repeat', 'tail')):
            for раунд in range(п.раунды):
                порядок = ('ручной', 'фасад') if раунд % 2 == 0 else ('фасад', 'ручной')
                пара = []
                for вариант in порядок:
                    каталог = приватный / f'{сценарий}-{раунд}-{вариант}'; каталог.mkdir(mode=0o700)
                    результат = измерить_ROOT(вариант, каталог) if п.контур=='root5' else измерить(вариант, сценарий, каталог)
                    данные.append(результат); пара.append(результат)
                    if результат['код']: код = 1; break
                if код: break
                м.требовать(пара[0]['фикстура']['ROOT'] == пара[1]['фикстура']['ROOT']
                    and (п.контур=='root5' or пара[0]['фикстура']['own']['байтов'] == пара[1]['фикстура']['own']['байтов'])
                    and пара[0]['фикстура']['тест'] == пара[1]['фикстура']['тест'], 'непарные первичные фикстуры')
                if п.контур=='root5':
                    м.требовать(пара[0]['фикстура']['команды']==пара[1]['фикстура']['команды'], 'разная семантика команд ROOT')
                м.требовать([(с['стадия'], с['код']) for с in пара[0]['стадии']] ==
                    [(с['стадия'], с['код']) for с in пара[1]['стадии']], 'разные наблюдённые последовательности')
            if код: break
    except (ValueError, OSError, KeyError, TypeError, м.свежесть.ProjectFilesError, м.коммит.отчёты.ОшибкаОтчёта) as ошибка:
        сырые = str(ошибка).encode()
        дескриптор = os.open(приватный / 'исходный-отказ.txt', os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(дескриптор, 'wb') as поток: поток.write(сырые)
        код = 1; данные.append({'класс_отказа': type(ошибка).__name__, 'исходный_отказ_sha256': м.хэш(сырые), 'байтов': len(сырые)})
    итог = {'код': код, 'раунды': п.раунды, 'контур':п.контур, 'наблюдения': данные,
        'граница': 'Setup, seed и рост источников вне таймера. Сравниваются способы композиции одинаковых прежних CLI; не before/after maker. Диагностика реальных именованных reader returns включена в wall обеих сторон. Подпроцессы wrapper и прямое ordinary prefix-чтение вне этих счётчиков: unknown, не0. Кэш ОС не сбрасывался; bytes логические, физический I/O unknown. SHA разных физических привязок сохраняются отдельно; equality всего raw native/cursor/v4 не утверждается.'}
    дескриптор = os.open(выход, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'wb') as поток: поток.write(м.байты(итог))
    print(json.dumps({'код': код, 'наблюдений': len(данные)}, ensure_ascii=False))
    return код



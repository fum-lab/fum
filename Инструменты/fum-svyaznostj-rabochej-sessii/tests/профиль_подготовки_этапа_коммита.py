    индекс = Path(м.поручения._гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index'))
    ожидаемый_индекс = м.хэш(индекс.read_bytes())
    class Остановить(Exception):
        pass
    def граница():
        м.коммит.адрес(п)
        м.требовать(м.хэш(индекс.read_bytes()) == ожидаемый_индекс, 'дрейф индекса')
        for ф in защищённые:
            м.приватный(ф)
            м.требовать(м.хэш(ф.read_bytes()) == план['снимок']['файлы'][str(ф)]['sha256'], 'дрейф входа')
    def команда(название, аргументы, *, индексировать=False):
        nonlocal ожидаемый_индекс
        граница(); результат = исполнить(аргументы, корень); стадии.append({'стадия': название, **результат})
        if результат['код']: raise Остановить()
        м.коммит.адрес(п)
        if индексировать: ожидаемый_индекс = м.хэш(индекс.read_bytes())
        else: граница()
        return результат
    обёртка = м.ИНСТРУМЕНТЫ / 'fum-otchyotyi-o-zapuskakh-proverok/scripts/отчёты_о_запусках_проверок.py'

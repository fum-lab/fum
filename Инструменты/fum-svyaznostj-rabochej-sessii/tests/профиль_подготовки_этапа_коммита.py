def новый_повтор(ф):
    п = copy.deepcopy(ф.п); каталог, записи = м.история(ф.корень, п['запрос'])
    номер = max(з['порядок'] for _, з, _ in записи) + 1
    идентификаторы = [str(uuid.uuid4()), str(uuid.uuid4())]
    будущие = [(каталог / f'{номер + смещение}_{идентификатор}.json').relative_to(ф.корень).as_posix() for смещение, идентификатор in enumerate(идентификаторы)]
    п['разрешённые_цели'] += будущие
    for роль in ('сообщение', 'подготовка', 'квитанция'): п[роль] = str(ф.приватный / f'повтор-{роль}.json')
    разрешение = ф.сохранить('повтор-разрешение.json', п['разрешённые_цели'])
    наполнение = copy.deepcopy(ф.наполнение)
    наполнение.update(разрешение={'путь': str(разрешение), 'sha256': м.хэш(разрешение.read_bytes())}, ожидаемые_цели=будущие)
    вход = copy.deepcopy(ф.вход)
    вход.update(вход_коммита=str(ф.сохранить('повтор-вход.json', п)), поручение=str(ф.сохранить('повтор-выбор.json', ф.д.выбор)),
        наполнение=str(ф.сохранить('повтор-наполнение.json', наполнение)), план_наполнения=str(ф.приватный / 'повтор-fill-plan.json'), повтор=True)
    вход['проверки'][0].update(идентификатор=идентификаторы[0], порядок=номер)
    вход['связность'].update(идентификатор=идентификаторы[1], порядок=номер + 1)
    return вход, п



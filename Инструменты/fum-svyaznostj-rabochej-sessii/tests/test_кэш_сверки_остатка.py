"""Ускорение сохраняет полный остаток и свежие границы доказательства."""
import json
import os
import unittest
from pathlib import Path
from unittest import mock

import test_обработка_сообщений as фикстура

МОДУЛЬ = фикстура.МОДУЛЬ
ЗАДАЧА = фикстура.ЗАДАЧА


class ПроверкаКэша(unittest.TestCase):
    # Переиспользуются открытые фикстуры, а не все тесты родительского класса.
    setUp = фикстура.ПроверкаОбработки.setUp
    гит = фикстура.ПроверкаОбработки.гит
    коммит = фикстура.ПроверкаОбработки.коммит
    добавить = фикстура.ПроверкаОбработки.добавить
    свидетельство = фикстура.ПроверкаОбработки.свидетельство
    предложение = фикстура.ПроверкаОбработки.предложение
    сохранить = фикстура.ПроверкаОбработки.сохранить

    def остаток(проверка, **параметры):
        return МОДУЛЬ.получить_остаток(проверка.источник, ЗАДАЧА,
            корень_репозитория=проверка.корень, кэш=проверка.кэш, **параметры)

    def подготовить(проверка, версий=4):
        снимок = проверка.остаток()
        проверка.сохранить(проверка.предложение(снимок), снимок)
        проверка.коммит()
        for номер in range(версий):
            with (проверка.корень / проверка.отчёт).open('a') as поток:
                поток.write(f'Дополнение {номер}.\n')
            проверка.коммит()

    def сравнить(проверка):
        полный = проверка.остаток(перепроверить=True)
        быстрый = проверка.остаток()
        проверка.assertEqual({к: з for к, з in полный.items() if к != 'профиль'},
                            {к: з for к, з in быстрый.items() if к != 'профиль'})
        return быстрый

    def путь_кэша(проверка):
        return проверка.кэш.with_name(проверка.кэш.name + '.свидетельства')

    def test_повтор_использует_исторические_сверки_но_не_готовый_остаток(проверка):
        проверка.подготовить()
        холодный = проверка.сравнить()
        тёплый = проверка.сравнить()
        проверка.assertGreater(холодный['профиль']['исторические_свидетельства']['перепроверено'], 0)
        проверка.assertEqual(тёплый['профиль']['исторические_свидетельства']['перепроверено'], 0)
        проверка.assertGreater(тёплый['профиль']['исторические_свидетельства']['переиспользовано'], 0)
        (проверка.корень / проверка.отчёт).write_text('Повреждение.\n')
        проверка.assertTrue(проверка.сравнить()['остаток'])

    def test_полная_перепроверка_не_читает_кэш_свидетельств(проверка):
        проверка.подготовить()
        проверка.остаток()
        проверка.путь_кэша().write_text('повреждение')
        полный = проверка.остаток(перепроверить=True)
        проверка.assertEqual(полный['остаток'], [])
        проверка.assertEqual(полный['профиль']['исторические_свидетельства']['переиспользовано'], 0)
        проверка.assertEqual(проверка.путь_кэша().read_text(), 'повреждение')
        with проверка.assertRaises(МОДУЛЬ.ОшибкаОбработки):
            проверка.остаток()

    def test_режим_без_записи_не_создаёт_файл_или_замок(проверка):
        проверка.подготовить()
        до = {п.name: п.read_bytes() for п in проверка.каталог.iterdir() if п.is_file()}
        with mock.patch.object(МОДУЛЬ.читатель, '_установить', side_effect=AssertionError('запись запрещена')), \
             mock.patch.object(МОДУЛЬ.читатель, '_замок', side_effect=AssertionError('замок запрещён')):
            итог = проверка.остаток(без_записи=True)
        проверка.assertEqual(итог['остаток'], [])
        проверка.assertEqual(до, {п.name: п.read_bytes() for п in проверка.каталог.iterdir() if п.is_file()})
        проверка.assertFalse(проверка.путь_кэша().exists())

    def test_удаление_и_возврат_свидетельства_не_стирают_разрыв(проверка):
        проверка.подготовить()
        проверка.остаток()
        путь = проверка.корень / проверка.отчёт
        прежние = путь.read_bytes()
        путь.unlink()
        проверка.коммит()
        путь.write_bytes(прежние)
        проверка.коммит()
        проверка.assertTrue(проверка.сравнить()['остаток'])

    def test_новый_режим_того_же_объекта_перепроверяется(проверка):
        проверка.подготовить()
        проверка.остаток()
        проверка.гит('update-index', '--chmod=+x', проверка.отчёт)
        os.chmod(проверка.корень / проверка.отчёт, 0o755)
        проверка.коммит()
        итог = проверка.сравнить()
        проверка.assertEqual(итог['профиль']['исторические_свидетельства']['перепроверено'], 1)

    def test_поздняя_отмена_не_скрывается_тёплым_кэшем(проверка):
        проверка.подготовить()
        проверка.остаток()
        проверка.добавить('Позднее уточнение.\n', 2)
        снимок = проверка.сравнить()
        проверка.assertIn('новый поздний ввод', снимок['остаток'][0]['причины'])
        предложение = проверка.предложение(снимок)
        предложение.update(актуальность='отменено', поздние=[снимок['сообщения'][1]['экземпляр']])
        проверка.сохранить(предложение, снимок)
        проверка.коммит()
        итог = проверка.сравнить()
        проверка.assertEqual([э['экземпляр'] for э in итог['остаток']], [снимок['сообщения'][1]['экземпляр']])

    def test_изменение_префикса_и_усечение_одинаково_отказывают(проверка):
        проверка.подготовить()
        проверка.остаток()
        исходные = проверка.источник.read_bytes()
        for байты in (исходные.replace('Сделай'.encode(), 'Делай!'.encode()), исходные.splitlines(keepends=True)[0]):
            with проверка.subTest(байты=len(байты)):
                проверка.источник.write_bytes(байты)
                for параметры in ({}, {'перепроверить': True}):
                    with проверка.assertRaises(МОДУЛЬ.ОшибкаОбработки):
                        проверка.остаток(**параметры)
                проверка.источник.write_bytes(исходные)

    def test_замена_источника_и_неполный_хвост_сохраняют_результат(проверка):
        проверка.подготовить()
        проверка.остаток()
        исходные = проверка.источник.read_bytes()
        временный = проверка.источник.with_suffix('.новый')
        временный.write_bytes(исходные)
        os.replace(временный, проверка.источник)
        проверка.assertEqual(проверка.сравнить()['остаток'], [])
        with проверка.источник.open('ab') as поток:
            поток.write(b'{"type":')
        проверка.assertFalse(проверка.сравнить()['полнота_источника'])
        with проверка.источник.open('ab') as поток:
            поток.write(b'"event_msg","payload":{}}\n')
        проверка.assertTrue(проверка.сравнить()['полнота_источника'])

    def test_смена_реализации_исключает_прежние_положительные_попадания(проверка):
        проверка.подготовить()
        проверка.остаток()
        with mock.patch.object(МОДУЛЬ, '_РЕАЛИЗАЦИЯ', 'f' * 64):
            итог = проверка.сравнить()
        проверка.assertGreater(итог['профиль']['исторические_свидетельства']['перепроверено'], 0)
        проверка.assertEqual(итог['профиль']['исторические_свидетельства']['переиспользовано'], 0)

    def test_подмена_ключей_кэша_не_даёт_ложного_попадания(проверка):
        проверка.подготовить()
        проверка.остаток()
        путь = проверка.путь_кэша()
        исходные = путь.read_bytes()
        for поле in ('запись_sha256', 'сообщение_sha256'):
            оболочка = json.loads(исходные)
            данные = оболочка['данные']
            ключ = next(iter(данные['проверено'].values()))
            ключ[поле] = '0' * 64
            # Обновление внешней суммы не заменяет проверку самих ключей.
            оболочка['sha256'] = МОДУЛЬ.хэш(МОДУЛЬ.читатель._байты(данные))
            путь.write_bytes(МОДУЛЬ.читатель._байты(оболочка))
            with проверка.subTest(поле=поле), проверка.assertRaises(МОДУЛЬ.ОшибкаОбработки):
                проверка.остаток()
        путь.write_bytes(исходные)

    def test_второй_родитель_с_разрывом_проверяется_при_том_же_объекте(проверка):
        проверка.подготовить(1)
        проверка.остаток()
        база = проверка.гит('rev-parse', 'HEAD').decode().strip()
        проверка.гит('checkout', '-qb', 'разрыв', база)
        путь = проверка.корень / проверка.отчёт
        исходные = путь.read_bytes()
        путь.unlink(); проверка.коммит()
        путь.write_bytes(исходные); проверка.коммит()
        проверка.гит('checkout', '-qb', 'цель', база)
        проверка.гит('merge', '--no-ff', '-m', 'Второй родитель', 'разрыв')
        проверка.assertTrue(проверка.сравнить()['остаток'])

    def test_чужая_идентичность_кэша_отклоняется(проверка):
        проверка.подготовить(1)
        проверка.остаток()
        путь = проверка.путь_кэша()
        исходные = путь.read_bytes()
        for поле, значение in (('задача', '00000000-0000-0000-0000-000000000178'), ('источник', '0' * 64)):
            оболочка = json.loads(исходные)
            оболочка['данные'][поле] = значение
            оболочка['sha256'] = МОДУЛЬ.хэш(МОДУЛЬ.читатель._байты(оболочка['данные']))
            путь.write_bytes(МОДУЛЬ.читатель._байты(оболочка))
            with проверка.subTest(поле=поле), проверка.assertRaises(МОДУЛЬ.ОшибкаОбработки):
                проверка.остаток()
        путь.write_bytes(исходные)

    def test_импортированные_события_индексируются_а_чужая_родословная_отклоняется(проверка):
        проверка.добавить('Позднее уточнение.\n', 2)
        база = проверка.гит('rev-parse', 'HEAD').decode().strip()
        родители = []
        for ветка, номер, текст in (('левая', 0, 'Сделай.\n'), ('правая', 1, 'Позднее уточнение.\n')):
            проверка.гит('checkout', '-qb', ветка, база)
            снимок = проверка.остаток()
            проверка.сохранить(проверка.предложение(снимок, номер, текст=текст), снимок)
            проверка.коммит()
            родители.append(проверка.гит('rev-parse', 'HEAD').decode().strip())
        объединение = МОДУЛЬ.подготовить_слияние_историй(проверка.корень, ЗАДАЧА, родители)
        проверка.гит('checkout', 'левая')
        процесс = фикстура.subprocess.run(['git', '-c', f'core.hooksPath={os.devnull}',
            'merge', '--no-ff', '--no-commit', 'правая'], cwd=проверка.корень, capture_output=True)
        проверка.assertNotEqual(процесс.returncode, 0)
        проверка.путь_истории.write_bytes(объединение['байты'])
        проверка.коммит()
        холодный = проверка.сравнить()
        тёплый = проверка.сравнить()
        проверка.assertEqual(тёплый['остаток'], [])
        проверка.assertGreater(холодный['профиль']['исторические_свидетельства']['перепроверено'], 0)
        проверка.assertEqual(тёплый['профиль']['исторические_свидетельства']['перепроверено'], 0)
        # Тот же blob на вершине без родителей не доказывает ancestry импортов.
        дерево = проверка.гит('rev-parse', 'HEAD^{tree}').decode().strip()
        чужой = проверка.гит('commit-tree', дерево, '-m', 'Несвязанный снимок').decode().strip()
        проверка.гит('checkout', '--detach', чужой)
        for параметры in ({}, {'перепроверить': True}):
            with проверка.assertRaises(МОДУЛЬ.ОшибкаОбработки):
                проверка.остаток(**параметры)

    def test_заключительный_дрейф_не_сохраняет_холодные_сверки(проверка):
        for дрейф in ('источник', 'свидетельство', 'история', 'HEAD', 'MERGE_HEAD'):
            with проверка.subTest(дрейф=дрейф):
                # Отдельная фикстура для каждого необратимого дрейфа.
                другая = ПроверкаКэша('test_повтор_использует_исторические_сверки_но_не_готовый_остаток')
                другая.setUp()
                проверка.addCleanup(другая.doCleanups)
                другая.подготовить(1)
                исходная = МОДУЛЬ.вычислить_остаток
                def изменить(*аргументы):
                    итог = исходная(*аргументы)
                    if дрейф == 'источник':
                        другая.добавить('Позднее уточнение.\n', 2)
                    elif дрейф == 'свидетельство':
                        (другая.корень / другая.отчёт).write_text('Подмена.\n')
                    elif дрейф == 'история':
                        другая.путь_истории.write_bytes(другая.путь_истории.read_bytes() + b'\n')
                    elif дрейф == 'HEAD':
                        другая.гит('commit', '--allow-empty', '-qm', 'Дрейф')
                    else:
                        каталог = Path(другая.гит('rev-parse', '--absolute-git-dir').decode().strip())
                        (каталог / 'MERGE_HEAD').write_bytes(другая.гит('rev-parse', 'HEAD'))
                    return итог
                with mock.patch.object(МОДУЛЬ, 'вычислить_остаток', side_effect=изменить), \
                     проверка.assertRaises(МОДУЛЬ.ОшибкаОбработки):
                    другая.остаток()
                проверка.assertFalse(другая.путь_кэша().exists())

    def test_утрата_исторического_объекта_не_скрывается_попаданием(проверка):
        проверка.подготовить()
        проверка.остаток()
        объект = проверка.гит('rev-parse', f'HEAD~2:{проверка.отчёт}').decode().strip()
        # Только временный репозиторий открытой фикстуры; общий Git не затронут.
        путь = проверка.корень / '.git/objects' / объект[:2] / объект[2:]
        проверка.assertTrue(путь.is_file())
        путь.unlink()
        проверка.assertTrue(проверка.сравнить()['остаток'])

    def test_дрейф_во_время_публикации_повторно_сверяется(проверка):
        проверка.подготовить(1)
        исходная = МОДУЛЬ.ускорение.СеансСверки.сохранить
        def изменить(сеанс):
            итог = исходная(сеанс)
            проверка.добавить('Позднее уточнение.\n', 2)
            return итог
        with mock.patch.object(МОДУЛЬ.ускорение.СеансСверки, 'сохранить', изменить), \
             проверка.assertRaises(МОДУЛЬ.ОшибкаОбработки):
            проверка.остаток()

    def test_неизменные_объекты_сверяются_один_раз_в_холодном_вызове(проверка):
        проверка.подготовить(0)
        for номер in range(4):
            (проверка.корень / 'пояснение.md').write_text(str(номер))
            проверка.коммит()
        итог = проверка.сравнить()
        проверка.assertEqual(итог['профиль']['исторические_свидетельства']['перепроверено'], 1)
        проверка.assertEqual(итог['профиль']['исторические_свидетельства']['переиспользовано'], 4)



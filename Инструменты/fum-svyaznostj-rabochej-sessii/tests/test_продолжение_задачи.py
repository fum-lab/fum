import json
import io
import importlib.util
from unittest import mock
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


СЦЕНАРИЙ = Path(__file__).resolve().parents[1] / "scripts" / "проверить-продолжение-задачи.py"
ИДЕНТИФИКАТОР = "00000000-0000-0000-0000-000000000001"


class ПродолжениеЗадачи(unittest.TestCase):
    def setUp(это):
        это.корень = Path(это.enterContext(tempfile.TemporaryDirectory())).resolve()
        это.запрос = "Журнал/2026-09-08_18-50-08_MSK_устранить-остановку/запрос.md"
        путь = это.корень / это.запрос
        путь.parent.mkdir(parents=True)
        путь.write_text("# Источник\n\n## Текст запроса\n\nПродолжай планирование.\n\nОстановись.\n\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: " + ИДЕНТИФИКАТОР + "\n", encoding="utf-8")
        это.план = {"схема": "fum.продолжение-задачи.1", "задача": ИДЕНТИФИКАТОР,
                    "режим": "постоянная", "остановка": None,
                    "работы": [{"идентификатор": "план", "действие": "Описать границу снимка",
                                "состояние": "доступна", "основание": {"запрос": это.запрос, "цитата": "Продолжай планирование."}, "свидетельство": None}]}

    def вызвать(это, *аргументы):
        путь = это.корень / "план.json"
        путь.write_text(json.dumps(это.план, ensure_ascii=False), encoding="utf-8")
        return subprocess.run([sys.executable, str(СЦЕНАРИЙ), "--корень-репозитория", str(это.корень),
                               "--план", "план.json", "--codex-thread-id", ИДЕНТИФИКАТОР, *аргументы],
                              capture_output=True, text=True)

    def test_оба_вида_коммита_не_разрешают_остановку(это):
        for вид in ("контрольный", "итоговый-этапа"):
            with это.subTest(вид=вид):
                результат = это.вызвать("--вид-коммита", вид, "--перед-завершением")
                это.assertEqual(результат.returncode, 3, результат.stderr)
                ответ = json.loads(результат.stdout)
                это.assertEqual(ответ["решение"], "продолжить")
                это.assertEqual(ответ["следующая_работа"], "план")

    def test_чтение_следующего_шага_успешно_и_не_пишет(это):
        результат = это.вызвать()
        это.assertEqual(результат.returncode, 0, результат.stderr)
        это.assertEqual(json.loads(результат.stdout)["решение"], "продолжить")
        это.assertEqual(len(list(это.корень.rglob("*"))), 4)

    def test_ожидание_не_скрывает_независимую_работу(это):
        ожидание = dict(это.план["работы"][0], идентификатор="вопрос", состояние="ожидает-ответа", свидетельство="Требуется выбрать формат.")
        это.план["работы"].insert(0, ожидание)
        это.assertEqual(json.loads(это.вызвать().stdout)["решение"], "продолжить")
        это.план["работы"].pop()
        результат = это.вызвать("--перед-завершением")
        это.assertEqual(результат.returncode, 0, результат.stderr)
        это.assertEqual(json.loads(результат.stdout)["решение"], "ожидать-ответа")

    def test_завершение_требует_свидетельства(это):
        это.план["работы"][0]["состояние"] = "завершена"
        это.assertEqual(это.вызвать().returncode, 2)
        это.план["работы"][0]["свидетельство"] = "Проверенный документ и локальный коммит."
        результат = это.вызвать("--перед-завершением")
        это.assertEqual(результат.returncode, 3, результат.stderr)
        это.assertEqual(json.loads(результат.stdout)["решение"], "продолжить")

    def test_явная_остановка_имеет_приоритет(это):
        путь = это.корень / это.запрос
        путь.write_text(путь.read_text().replace("Продолжай планирование.\n\n", ""))
        это.план["остановка"] = {"запрос": это.запрос, "цитата": "Остановись."}
        результат = это.вызвать("--перед-завершением")
        это.assertEqual(результат.returncode, 0, результат.stderr)
        это.assertEqual(json.loads(результат.stdout)["решение"], "остановлено-пользователем")

    def test_подмена_задачи_источника_и_состояния_отклоняется(это):
        варианты = [("задача", "чужая"), ("схема", "неизвестная"), ("режим", "автоматическая")]
        for ключ, значение in варианты:
            исходное = это.план[ключ]
            это.план[ключ] = значение
            это.assertEqual(это.вызвать().returncode, 2)
            это.план[ключ] = исходное
        это.план["работы"][0]["основание"]["цитата"] = "Несуществующая команда"
        это.assertEqual(это.вызвать().returncode, 2)

    def test_остановка_не_требует_непустого_остатка(это):
        путь = это.корень / это.запрос
        путь.write_text(путь.read_text().replace("Продолжай планирование.\n\n", ""))
        это.план["остановка"] = {"запрос": это.запрос, "цитата": "Остановись."}
        это.план["работы"] = []
        результат = это.вызвать("--перед-завершением")
        это.assertEqual(результат.returncode, 0, результат.stderr)
        это.assertEqual(json.loads(результат.stdout)["решение"], "остановлено-пользователем")

    def test_идентификатор_читается_только_из_служебного_раздела(это):
        путь = это.корень / это.запрос
        текст = путь.read_text().replace("Продолжай планирование.", "Продолжай планирование.\n\n````text\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: чужая-задача\n````")
        путь.write_text(текст)
        это.assertEqual(это.вызвать().returncode, 0)
        путь.write_text(текст.rsplit("## Идентификатор сеанса Codex", 1)[0])
        это.assertEqual(это.вызвать().returncode, 2)

    def test_повторное_основание_читается_один_раз_за_вызов(это):
        описание = importlib.util.spec_from_file_location("продолжение", СЦЕНАРИЙ)
        модуль = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(модуль)
        это.план["работы"].append(dict(это.план["работы"][0], идентификатор="вторая"))
        исходное = Path.read_text
        with mock.patch.object(Path, "read_text", autospec=True, side_effect=исходное) as чтение:
            ответ = модуль.определить_продолжение(это.корень, это.план, ИДЕНТИФИКАТОР)
            это.assertEqual(ответ["решение"], "продолжить")
            это.assertEqual(чтение.call_count, 1)
        (это.корень / это.запрос).write_text("Источник изменён.")
        with это.assertRaises(модуль.ОшибкаПродолжения):
            модуль.определить_продолжение(это.корень, это.план, ИДЕНТИФИКАТОР)

    def test_повторные_ключи_объекта_не_заменяют_доступную_работу(это):
        завершённая = dict(это.план["работы"][0], состояние="завершена", свидетельство="Готово.")
        текст = json.dumps(это.план, ensure_ascii=False)[:-1] + ', "работы": ' + json.dumps([завершённая], ensure_ascii=False) + '}'
        (это.корень / "план.json").write_text(текст)
        результат = subprocess.run([sys.executable, str(СЦЕНАРИЙ), "--корень-репозитория", str(это.корень), "--план", "план.json", "--codex-thread-id", ИДЕНТИФИКАТОР, "--перед-завершением"], capture_output=True, text=True)
        это.assertEqual(результат.returncode, 2, результат.stdout)

    def test_отказ_профиля_не_меняет_решение(это):
        (это.корень / "план.json").write_text(json.dumps(это.план, ensure_ascii=False))
        описание = importlib.util.spec_from_file_location("продолжение", СЦЕНАРИЙ)
        модуль = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(модуль)
        аргументы = [str(СЦЕНАРИЙ), "--корень-репозитория", str(это.корень), "--план", "план.json", "--codex-thread-id", ИДЕНТИФИКАТОР, "--перед-завершением", "--профиль"]
        with mock.patch.object(sys, "argv", аргументы), mock.patch.object(sys, "stdout", io.StringIO()), mock.patch.object(sys, "stderr", mock.Mock(write=mock.Mock(side_effect=OSError("Диагностический канал закрыт")))):
            это.assertEqual(модуль.выполнить(), 3)

    def test_пустой_план_не_доказывает_завершение(это):
        это.план["работы"] = []
        это.assertEqual(это.вызвать("--перед-завершением").returncode, 2)

    def test_выход_и_ссылка_в_пути_источника_отклоняются(это):
        это.план["работы"][0]["основание"]["запрос"] = "../запрос.md"
        это.assertEqual(это.вызвать().returncode, 2)
        ссылка = это.корень / "ссылка"
        ссылка.symlink_to(это.корень / "Журнал", target_is_directory=True)
        это.план["работы"][0]["основание"]["запрос"] = это.запрос.replace("Журнал", "ссылка")
        это.assertEqual(это.вызвать().returncode, 2)


if __name__ == "__main__":
    unittest.main()

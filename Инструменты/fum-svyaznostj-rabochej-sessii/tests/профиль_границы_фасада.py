def сверить_загруженный_код(модуль, файл, имена):
    if Path(модуль.__file__) != файл or файл.resolve() != файл:
        raise ValueError('загружен модуль из другого checkout')
    скомпилирован = compile(файл.read_bytes(), str(файл), 'exec')
    функции = {код.co_name: код for код in скомпилирован.co_consts
        if isinstance(код, types.CodeType)}
    for имя in имена:
        функция = getattr(модуль, имя)
        код = функция.__code__; ожидаемый = функции[имя]
        # marshal сохраняет также внутреннее разделение ссылок на константы:
        # равные CodeType могут иметь разные сериализованные байты.
        положение = ('co_filename', 'co_firstlineno', 'co_linetable', 'co_exceptiontable')
        if (функция.__globals__ is not vars(модуль)
                or код != ожидаемый
                or any(getattr(код, поле) != getattr(ожидаемый, поле) for поле in положение)):
            raise ValueError('загруженная функция отличается от текущих исходников')


def пины_зависимостей(корень):
    результат = {}
    for модуль in list(sys.modules.values()):
        имя = getattr(модуль, '__file__', None)
        if not isinstance(имя, str):
            continue
        файл = Path(имя)
        if not файл.is_relative_to(корень / 'Инструменты'):
            continue
        if файл.resolve() != файл or not файл.is_file():
            raise ValueError('нефизическая зависимость профиля')
        до = файл.stat(); сырые = файл.read_bytes(); после = файл.stat()
        def метка(с):
            return [с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink,
                с.st_size, с.st_mtime_ns, с.st_ctime_ns]
        if not stat.S_ISREG(до.st_mode) or метка(до) != метка(после):
            raise ValueError('зависимость изменилась при чтении')
        результат[файл.relative_to(корень).as_posix()] = {
            'sha256': hashlib.sha256(сырые).hexdigest(), 'идентичность': метка(до)}
    return результат


def исходный_вызов(модуль, сырые):
    """Общий код не меняется; две прежние функции получают общие зависимости."""
    прежнее = ast.parse(сырые)
    текущее = ast.parse(Path(модуль.__file__).read_bytes())
    выбранные = {'_контекст_независимого_фасада', '_сверить_новую_границу'}
    пропуск = выбранные | {'_загрузить_контекст_независимого_фасада'}

    def остальное(дерево):
        return [ast.dump(узел, include_attributes=False) for узел in дерево.body
            if not isinstance(узел, ast.FunctionDef) or узел.name not in пропуск]

    if остальное(прежнее) != остальное(текущее):
        raise ValueError('базис отличается вне выбранных функций границы')
    функции = [узел for узел in прежнее.body
        if isinstance(узел, ast.FunctionDef) and узел.name in выбранные]
    if {узел.name for узел in функции} != выбранные or len(функции) != 2:
        raise ValueError('нет двух точных функций базиса')
    пространство = dict(vars(модуль))
    exec(compile(ast.Module(body=функции, type_ignores=[]),
        модуль.__file__, 'exec'), пространство)
    return пространство['_сверить_новую_границу']


def измерить(модуль, функция, вход, план, выбор):
    журнал = модуль._независимый_журнал()
    штатная = журнал.проверить_область_записей
    интервалы = []

    def наблюдать(*аргументы, **поля):
        начало = time.perf_counter_ns()
        try:
            return штатная(*аргументы, **поля)
        finally:
            интервалы.append(time.perf_counter_ns() - начало)

    with mock.patch.object(журнал, 'проверить_область_записей', наблюдать):
        начало = time.perf_counter_ns()
        результат = функция(вход, план, выбор)
        длительность = time.perf_counter_ns() - начало
    return результат, {'длительность_нс': длительность,
        'полные_сверки_нс': интервалы, 'число_полных_сверок': len(интервалы)}


def профиль(базис, число):
    # Сохраняем среду вызывающего процесса; дочерние Git фикстуры не получают
    # перенаправления через GIT_DIR, alternate objects или config environment.
    среда = {ключ: значение for ключ, значение in os.environ.items()
        if not ключ.startswith('GIT_')}
    with mock.patch.dict(os.environ, среда, clear=True):
        return _профиль(базис, число)


def _профиль(базис, число):
    корень = Path(__file__).resolve().parents[3]
    путь = 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/подготовка_этапа_коммита.py'
    if not re.fullmatch(r'[0-9a-f]{40}|[0-9a-f]{64}', базис):
        raise ValueError('нужен полный OID принятого базиса')
    файл = корень / путь
    код_до = файл.read_bytes()
    помощник = открытый.ПерваяПодготовкаОткрытогоЭтапа()
    try:
        модуль, рабочий, вход, выбор, _, _ = помощник.открытый_стенд()
        журнал = модуль._независимый_журнал()
        сверить_загруженный_код(модуль, файл, {
            '_контекст_независимого_фасада', '_загрузить_контекст_независимого_фасада',
            '_сверить_новую_границу'})
        сверить_загруженный_код(журнал, файл.with_name('связность_независимого_журнала.py'),
            {'проверить_область_записей'})
        гит = журнал.журнал()._гит
        if гит(корень, 'cat-file', '-t', базис) != b'commit\n':
            raise ValueError('базис не является точным commit-объектом')
        сырые = гит(корень, 'show', базис + ':' + путь)
        старая = исходный_вызов(модуль, сырые)
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
            план = модуль.построить_план(вход, выбранный_состав=выбор)
            до = снимок(рабочий.ф.каталог)
            зависимости = пины_зависимостей(корень)
            пары = []
            for номер in range(число):
                порядок = ('базис', 'кандидат') if номер % 2 == 0 else ('кандидат', 'базис')
                замеры = {}; результаты = {}
                for имя in порядок:
                    функция = старая if имя == 'базис' else модуль._сверить_новую_границу
                    результаты[имя], замеры[имя] = измерить(
                        модуль, функция, вход, план, выбор)
                    if снимок(рабочий.ф.каталог) != до:
                        raise ValueError('граница записала данные фикстуры')
                if результаты['базис'] != результаты['кандидат']:
                    raise ValueError('различается результат успешной границы')
                if (замеры['базис']['число_полных_сверок'],
                        замеры['кандидат']['число_полных_сверок']) != (2, 1):
                    raise ValueError('не подтверждён переход двух полных сверок в одну')
                пары.append({'порядок': list(порядок), 'замеры': замеры,
                    'результат_равен': True, 'фикстура_неизменна': True})
        if файл.read_bytes() != код_до:
            raise ValueError('код изменился во время профиля')
        if пины_зависимостей(корень) != зависимости:
            raise ValueError('зависимости профиля изменились')
        сверить_загруженный_код(модуль, файл, {
            '_контекст_независимого_фасада', '_загрузить_контекст_независимого_фасада',
            '_сверить_новую_границу'})
        сверить_загруженный_код(журнал, файл.with_name('связность_независимого_журнала.py'),
            {'проверить_область_записей'})
        return {'схема': 'fum.профиль-границы-фасада.1', 'базис': базис,
            'базис_sha256': hashlib.sha256(сырые).hexdigest(),
            'кандидат_sha256': hashlib.sha256(код_до).hexdigest(),
            'зависимостей': len(зависимости), 'зависимости_неизменны': True,
            'пары': пары, 'граница': 'Один процесс и одна малая временная '
                'Git-фикстура; setup, план и снимки вне измеряемого окна. '
                'Интервалы полной области вложены в wall и не суммируются с ним. '
                'Это компонентное наблюдение, не время большого ROOT или Create; '
                'влияние кэша ОС и независимость выборок не доказаны.'}
    finally:
        помощник.doCleanups()


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--базис', required=True)
    разбор.add_argument('--число-пар', type=int, default=3, choices=range(1, 11))
    аргументы = разбор.parse_args()
    результат = профиль(аргументы.базис, аргументы.число_пар)
    print(json.dumps(результат, ensure_ascii=False, sort_keys=True))


if __name__ == '__main__':
    главная()

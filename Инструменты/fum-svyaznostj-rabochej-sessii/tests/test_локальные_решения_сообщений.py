    def сбой_повторного_fsync(проверка, вид, исходная):
        import stat
        def отказ(дескриптор):
            режим = os.fstat(дескриптор).st_mode
            if (вид == 'файл' and stat.S_ISREG(режим)) or (вид == 'каталог' and stat.S_ISDIR(режим)):
                raise OSError('Повторный сбой fsync при восстановлении')
            return исходная(дескриптор)
        return отказ


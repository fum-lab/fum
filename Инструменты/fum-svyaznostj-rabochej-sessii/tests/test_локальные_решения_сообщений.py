    def гит(проверка, *аргументы):
        return subprocess.check_output(['git', '-c', 'core.hooksPath=' + os.devnull, *аргументы],
                                       cwd=проверка.корень, stderr=subprocess.PIPE)

    def коммит(проверка):
        проверка.гит('add', '.')
        проверка.гит('commit', '-qm', 'Сохранить открытую фикстуру')

    def добавить(проверка, текст, номер, *, неизвестное=False):
        запись = {'type': 'response_item', 'payload': {'type': 'message', 'role': 'user',
            'id': f'msg_{номер}', 'content': [{'type': 'input_text', 'text': текст}]}}
        if not неизвестное:
            запись['payload']['internal_chat_message_metadata_passthrough'] = {'content_item_kinds': ['user.text']}
        with проверка.источник.open('ab') as поток:
            поток.write(строка(запись))

    def прочитать(проверка):
        return слой.прочитать_локальные_решения(проверка.источник, ЗАДАЧА, корень_репозитория=проверка.корень)

    def свидетельство(проверка, путь, текст):
        байты = (проверка.корень / путь).read_bytes()
        часть = текст.encode()
        начало = байты.index(часть)
        return {'путь': путь, 'начало': начало, 'конец': начало + len(часть), 'sha256': штатная.хэш(часть)}

    def предложение(проверка, снимок, номер=0, *, текст='Сделай.\n'):
        return {'экземпляр': снимок['контекст']['экземпляры'][номер], 'контекст': снимок['контекст'],
            'решение': 'работа', 'актуальность': 'актуально', 'поздние': [],
            'команда': {**проверка.свидетельство(проверка.запрос, текст), 'формат': 'текст'},
            'ответ': проверка.свидетельство(проверка.отчёт, 'Команда принята в работу.\n'),
            'основание': проверка.свидетельство(проверка.отчёт, 'Основание сохранено.\n')}

    def параметры(проверка, снимок, запись=None):
        return dict(корень_репозитория=проверка.корень, запись=запись or проверка.предложение(снимок),
            ожидаемая_локальная_история=снимок['локальная_история_sha256'],
            ожидаемая_обычная_история=снимок['обычная_история_sha256'],
            ожидаемый_классификатор=снимок['классификатор_sha256'], ожидаемый_читатель=снимок['читатель_sha256'],
            допустимые_части_sha256=штатная.хэш(штатная.читатель._байты([{'type': 'input_text', 'text': 'Сделай.\n'}])))

    def сохранить(проверка, снимок, запись=None, **замены):
        параметры = проверка.параметры(снимок, запись)
        параметры.update(замены)
        return слой.сохранить_локальное_решение(проверка.источник, ЗАДАЧА, **параметры)


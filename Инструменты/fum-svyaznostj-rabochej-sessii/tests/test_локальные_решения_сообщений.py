    def test_контекст_CAS_версии_и_публикационный_допуск(проверка):
        снимок = проверка.прочитать()
        for поле in ('ожидаемая_локальная_история', 'ожидаемая_обычная_история',
                     'ожидаемый_читатель', 'ожидаемый_классификатор', 'допустимые_части_sha256'):
            with проверка.subTest(поле=поле), проверка.assertRaises(слой.ОшибкаЛокальногоРешения):
                проверка.сохранить(снимок, **{поле: '0' * 64})
        for случай in ('пропуск', 'порядок', 'хэш', 'граница', 'поле'):
            запись = copy.deepcopy(проверка.предложение(снимок))
            if случай == 'пропуск': запись['контекст']['экземпляры'].pop()
            if случай == 'порядок': запись['контекст']['экземпляры'].reverse()
            if случай == 'хэш': запись['контекст']['sha256'] = '0' * 64
            if случай == 'граница': запись['контекст']['граница'] -= 1
            if случай == 'поле': запись['завершение_задачи_доказано'] = True
            with проверка.subTest(случай=случай), проверка.assertRaises(слой.ОшибкаЛокальногоРешения):
                проверка.сохранить(снимок, запись)
        проверка.assertFalse(проверка.локальная.exists())


    def test_fsync_до_и_после_replace(проверка):
        снимок = проверка.прочитать()
        исходная = слой.читатель.os.fsync
        for фаза in ('временный', 'каталог'):
            def сбой(дескриптор):
                import stat
                режим = os.fstat(дескриптор).st_mode
                if фаза == 'временный' and stat.S_ISREG(режим): raise OSError('Сбой fsync файла')
                if фаза == 'каталог' and stat.S_ISDIR(режим) and проверка.локальная.exists():
                    raise OSError('Сбой fsync каталога после replace')
                return исходная(дескриптор)
            with mock.patch.object(слой.читатель.os, 'fsync', side_effect=сбой):
                with проверка.assertRaises(слой.НеизвестныйИсход): проверка.сохранить(снимок)
            if фаза == 'временный': проверка.assertFalse(проверка.локальная.exists())
        байты = проверка.локальная.read_bytes()
        проверка.assertTrue(проверка.сохранить(снимок)['повтор'])
        проверка.assertEqual(байты, проверка.локальная.read_bytes())

    def начать_неизвестную_установку(проверка):
        import stat
        снимок = проверка.прочитать()

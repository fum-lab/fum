"""Время первичной проверки и отдельного читающего повтора малой фикстуры."""
import json
import time

from test_проверки_кандидата_обратного_приёма import ПроверкаКандидата


def измерить():
    опыт = ПроверкаКандидата()
    опыт.setUp()
    try:
        начало = time.perf_counter_ns()
        результат = опыт.запустить()
        первичный = time.perf_counter_ns() - начало
        начало = time.perf_counter_ns()
        повтор = опыт.прочитать(результат)
        чтение = time.perf_counter_ns() - начало
        assert повтор['пригоден'] is True
        return {'схема': 'fum.профиль-проверки-кандидата.1', 'опытов': 1,
                'файлов': 1, 'первичный_нс': первичный, 'читающий_повтор_нс': чтение,
                'граница': 'Малая локальная Git-фикстура. Подготовка вне интервалов. '
                'Первичный вызов включает два наблюдения Git, один процесс и сохранение. '
                'Последующее чтение не запускает проверку и не обращается к Git. '
                'Это не время полной интеграции FUM и не сравнение с прежним контуром.'}
    finally:
        опыт.doCleanups()


if __name__ == '__main__':
    print(json.dumps(измерить(), ensure_ascii=False, sort_keys=True))

        сам.assertEqual([сам.нынешнее_поручение, сам.нынешнее_поручение], [команда['текст'] for команда in команды_стенда])
        сам.assertNotEqual(команды_стенда[0]['экземпляр'], команды_стенда[1]['экземпляр'])
        сам.документ['команды_этапа'].reverse()
        сам.выбрать_назначение(); сам.параметры['выбранное_поручение'] = сам.выбор

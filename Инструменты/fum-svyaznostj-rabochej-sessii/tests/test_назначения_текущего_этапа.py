    def делегация(сам, имя, текст):
        содержимое = {'type': 'function_call_output', 'name': имя,
            'output': '<codex_delegation>\n  <source_thread_id>' + сам.координатор + '</source_thread_id>\n  <input>' + текст + '</input>\n</codex_delegation>'}
        if имя == 'send_message_to_thread':
            содержимое['namespace'] = 'codex_app'
        return {'type': 'response_item', 'payload': содержимое}

    def гит_стенда(сам, *аргументы):
        return subprocess.check_output(['git', '-C', str(сам.корень_стенда), *аргументы], stderr=subprocess.PIPE).decode().strip()

    def выбрать_назначение(сам):
        файл_проверки = сам.корень_стенда / 'Планирование/назначение.json'
        файл_проверки.write_bytes(байты(сам.документ))
        сам.гит_стенда('add', '.')
        сам.гит_стенда('commit', '-qm', 'Независимое назначение ROOT')
        сам.выбор = {'координатор': сам.координатор, 'исполнитель': сам.писатель_стенда,
            'коммит': сам.гит_стенда('rev-parse', 'HEAD'), 'путь': 'Планирование/назначение.json', 'sha256': хэш_стенда(файл_проверки.read_bytes())}
        сам.гит_стенда('reset', '--hard', сам.коммит_основы)

    def проверить_назначение(сам, **параметры_вызова):
        with сам.модуль.выбрать(сам.выбор):
            return сам.модуль.проверить(сам.параметры, сам.выбор, **параметры_вызова)

    def ожидать_отказ(сам, действие):
        вершина = сам.гит_стенда('rev-parse', 'HEAD')
        индекс = (сам.корень_стенда / '.git/index').read_bytes()
        with сам.assertRaises(ValueError):
            действие()
        сам.assertEqual(вершина, сам.гит_стенда('rev-parse', 'HEAD'))
        сам.assertEqual(индекс, (сам.корень_стенда / '.git/index').read_bytes())


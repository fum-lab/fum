        for путь in РЕСУРСЫ:
            п = сам.корень/(ТЕМА+путь); п.parent.mkdir(parents=True, exist_ok=True)
            источник = КАТАЛОГ/Path(путь).name
            п.write_bytes(источник.read_bytes() if источник.exists() else b'not implemented\n')
        гит(сам.корень, 'add', 'Инструменты'); гит(сам.корень, 'commit', '-m', 'Ресурсы следующего этапа')

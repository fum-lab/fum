    def снимок(сам): return сам.ф.снимок()
    def закрепить(сам, данные):
        гит(сам.корень, 'switch', '-c', 'codex/план-повтора')
        (сам.корень/'Планирование').mkdir(exist_ok=True)
        сам.выбор = сам.ф.с.сохранить('Планирование/повторный-план.json', данные)
        return сам.выбор



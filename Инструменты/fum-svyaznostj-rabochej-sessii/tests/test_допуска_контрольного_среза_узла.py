def дописать(путь, запись):
    данные = запуск.байты(запись)
    начало = путь.stat().st_size
    with путь.open('ab') as поток:
        поток.write(данные); поток.flush(); os.fsync(поток.fileno())
    return {'начало':начало,'конец':начало+len(данные),
        'sha256':hashlib.sha256(данные).hexdigest()}



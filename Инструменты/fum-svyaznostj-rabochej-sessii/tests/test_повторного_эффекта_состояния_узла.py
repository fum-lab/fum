    def проверить_свежий_повтор(сам, ожидаемый, *, отрицательный=True):
        """Новый CLI после изъятия live-свидетельств; все снимки вне измерения."""
        ф = сам.ф
        вход = ф.приватный / 'CLI-вход-повтора.json'
        вход.write_bytes(байты(ф.вход_обновления)); вход.chmod(0o600)
        for номер, путь in enumerate(sorted({ф.нативный, ф.пример.ф.нативный})):
            путь.rename(ф.приватный / ('изъятый-источник-' + str(номер) + '.jsonl'))
        (ф.корень / ф.папка).rename(ф.приватный / 'изъятая-пара')
        for ветка in (ф.полномочия['контрольная_ветка'], ф.вход_обновления['контроль']['ветка']):
            гит(ф.корень, 'update-ref', '-d', ветка, гит(ф.корень, 'rev-parse', ветка))
        import обновление_ожиданий_узла as писатель
        команда = [sys.executable, '-B', писатель.__file__, 'повтор', '--вход', str(вход)]
        до = ф.снимок_метаданных()
        процесс = сам.измерить('свежий_повтор', subprocess.run, команда,
            capture_output=True, text=True, timeout=60, cwd=ф.корень)
        сам.assertEqual(процесс.returncode, 0, процесс.stderr)
        сам.assertEqual(json.loads(процесс.stdout), ожидаемый)
        сам.assertEqual(до, ф.снимок_метаданных())
        сам.assertEqual(гит(ф.корень, 'rev-list', '--count', ф.исходный_коммит + '..HEAD'), '1')
        if not отрицательный:
            return
        # Неизвестная квитанция не разрешает второй эффект и не переписывается.
        квитанция = Path(ф.параметры['квитанция'])
        документ = json.loads(квитанция.read_bytes()); документ['состояние'] = 'неизвестно'
        квитанция.write_bytes(байты(документ))
        до = ф.снимок_метаданных()
        отказ = subprocess.run(команда, capture_output=True, text=True, timeout=60, cwd=ф.корень)
        сам.assertEqual(отказ.returncode, 2, отказ.stderr)
        сам.assertEqual(до, ф.снимок_метаданных())



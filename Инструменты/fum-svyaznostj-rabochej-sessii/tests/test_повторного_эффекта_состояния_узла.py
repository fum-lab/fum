class ПовторныйЭффектСостояния(unittest.TestCase):
    def setUp(сам):
        временный = tempfile.TemporaryDirectory(prefix='fum-repeat-effect-')
        сам.addCleanup(временный.cleanup)
        сам.ф = ПримерПовторногоЭффекта(временный.name)

    def модуль_полномочий(сам):
        return importlib.import_module('полномочия_повторного_состояния_узла')

    def test_неверный_предел_профиля_отказывает_до_создания_каталога(сам):
        import профиль_повторного_эффекта_состояния_узла as профиль
        каталог = сам.ф.пример.ф.с.папка / 'неразрешённый-профиль'
        до = сам.ф.снимок_метаданных()
        for предел in (0, -1, True, 1201, 600.0, None):
            with сам.subTest(предел=предел), сам.assertRaises(ValueError):
                профиль.измерить_повторный_эффект(каталог, предел_процесса_секунд=предел)
            сам.assertFalse(каталог.exists())
            сам.assertEqual(до, сам.ф.снимок_метаданных())
        for аргументы in (
                ['--срез', 'повторный-эффект', '--предел-процесса-секунд', '1201'],
                ['--срез', 'потоковый', '--предел-процесса-секунд', '600'],
                ['--один-процесс', '--вариант', 'повторный-эффект', '--предел-процесса-секунд', '900']):
            процесс = subprocess.run([sys.executable, '-I', '-S', '-B', профиль.__file__,
                '--каталог', str(каталог), '--выход', str(каталог / 'выход.json'), *аргументы],
                capture_output=True, text=True, timeout=30)
            сам.assertEqual(процесс.returncode, 2, процесс.stderr)
            сам.assertIn('Предел', процесс.stderr)
            сам.assertFalse(каталог.exists())
            сам.assertEqual(до, сам.ф.снимок_метаданных())

    def test_профильный_образ_сохраняет_входы_без_исполняемой_сериализации(сам):
        import профиль_повторного_эффекта_состояния_узла as профиль
        ф = сам.ф
        ф.подготовить_исполнителя(); ф.подготовить_обновление()
        до = ф.снимок_метаданных()
        образ = профиль.упаковать_фикстуру(ф)
        восстановленная = профиль.распаковать_фикстуру(json.loads(байты(образ)))
        сам.assertEqual(профиль.упаковать_фикстуру(восстановленная), образ)
        сам.assertEqual(восстановленная.корень, ф.корень)
        сам.assertEqual(восстановленная.вход_обновления, ф.вход_обновления)
        сам.assertEqual(профиль.снимок_повторного_кода(), профиль.снимок_повторного_кода())
        сам.assertEqual(до, ф.снимок_метаданных())

    def test_жёсткая_ссылка_регистр_и_нормализация_не_разрешают_повтор_установки(сам):
        import unicodedata
        ф = сам.ф; ф.подготовить_исполнителя()
        журнал = importlib.import_module('журнал_повторного_состояния_узла')
        with patch.dict(os.environ, {'CODEX_THREAD_ID': ф.акт['исполнитель']}):
            журнал.установить(ф.параметры, доверенное_поручение=ф.выбор_акта)
            for имя in (ф.план['файлы'][0]['путь'].replace('Журнал/', 'журнал/', 1),
                    unicodedata.normalize('NFD', ф.план['файлы'][1]['путь'])):
                до = ф.снимок_метаданных()
                with сам.subTest(имя=имя), сам.assertRaises(ValueError):
                    журнал._точный_путь(ф.корень, имя)
                сам.assertEqual(до, ф.снимок_метаданных())
            os.link(ф.корень / ф.план['файлы'][0]['путь'], ф.приватный / 'жёсткая-копия.md')
            до = ф.снимок_метаданных()
            with сам.assertRaises(ValueError):
                журнал.установить(ф.параметры, доверенное_поручение=ф.выбор_акта)
            сам.assertEqual(до, ф.снимок_метаданных())

    def test_независимые_третьи_полномочия_связывают_план_и_новое_поколение(сам):
        ф = сам.ф
        до = ф.снимок()
        итог = сам.модуль_полномочий().прочитать(ф.корень, ф.выбор_полномочий)
        сам.assertEqual(итог['документ'], ф.полномочия)
        сам.assertEqual(итог['план_журнала']['значение'], ф.план)
        сам.assertEqual(итог['план_журнала']['источник'], ф.выбор_плана)
        сам.assertNotEqual(ф.пример.R, ф.исходный_коммит)
        сам.assertNotEqual(итог['документ']['поколение_полномочий'],
            ф.план['доверие']['поколение_полномочий'])
        сам.assertFalse(итог['разрешение_установки'])
        сам.assertEqual(до, ф.снимок())

    def test_прежние_полномочия_не_принимают_новую_схему(сам):
        for флаг in (False, True):
            with сам.subTest(новый_эффект=флаг), сам.assertRaises(ValueError):
                прежние_полномочия.прочитать(сам.ф.корень, сам.ф.выбор_полномочий,
                    новый_эффект=флаг)

    def test_подмена_плана_идентичности_базы_и_целей_закрывает_допуск(сам):
        ф = сам.ф
        варианты = [
            {'план_журнала': {**ф.выбор_плана, 'sha256': '0' * 64}},
            {'исходный_коммит': ф.пример.R},
            {'владелец': ф.полномочия['координатор']},
            {'узел': 'чужой-узел'},
            {'ветка': 'refs/heads/fuma'},
            {'поколение_полномочий': ф.план['поколение_полномочий']},
            {'цели': [*ф.цели, ф.цели[0]]},
        ]
        for замена in варианты:
            документ = {**copy.deepcopy(ф.полномочия), **замена}
            выбор = ф.сохранить_полномочия(документ)
            до = ф.снимок()
            with сам.subTest(замена=замена), сам.assertRaises(ValueError):
                сам.модуль_полномочий().прочитать(ф.корень, выбор)
            сам.assertEqual(до, ф.снимок())

    def test_историческое_чтение_после_смены_контроля_не_разрешает_новый_эффект(сам):
        ф = сам.ф
        модуль = сам.модуль_полномочий()
        гит(ф.корень, 'branch', '-f', 'codex/повторный-эффект', ф.пример.R)
        до = ф.снимок()
        with сам.assertRaises(ValueError):
            модуль.прочитать(ф.корень, ф.выбор_полномочий, новый_эффект=True)
        итог = модуль.прочитать(ф.корень, ф.выбор_полномочий, новый_эффект=False)
        сам.assertEqual(итог['документ'], ф.полномочия)
        сам.assertEqual(до, ф.снимок())

    def test_обычный_читатель_проверяет_новую_версию_без_установки_пары(сам):
        ф = сам.ф
        ф.подготовить_исполнителя()

class ПримерПовторногоЭффекта:
    """R и H различаются; P и A закреплены отдельными настоящими коммитами."""

    def __init__(сам, каталог, *, полный=False):
        сам.пример = ПримерПлана(каталог)
        сам.исходный_коммит = сам.пример.вход['исходный_коммит']
        сам.корень = сам.пример.корень
        if полный:
            сам.подготовить_базис()
        сам.сырые_плана = сам.пример.построить()['байты']
        сам.план = json.loads(сам.сырые_плана)
        assert сам.план['исходный_коммит'] == сам.исходный_коммит
        сам.выбор_плана = сам.пример.закрепить(сам.сырые_плана)
        сам.папка = Path(сам.план['файлы'][0]['путь']).parent
        сам.цели = [сам.план['доверие']['источник']['путь'],
            *[файл['путь'] for файл in сам.план['файлы']],
            str(сам.папка / 'материалы/история-модели.json'),
            'Журнал/README.md', 'Индексы/markdown-файлы-по-времени-редактирования.md',
            str(сам.папка / 'материалы/запуски-проверок/1_11111111-1111-4111-8111-111111111111.json')]
        сам.полномочия = {'схема': 'fum.полномочия-ветки-состояния-узла.3',
            **{ключ: сам.план[ключ] for ключ in прежние_полномочия.ИДЕНТИЧНОСТЬ},
            'поколение_полномочий': 'поколение-2',
            'ветка': сам.план['ветка'], 'хэш_корня': сам.план['хэш_корня'],
            'начальный_коммит': сам.план['первоначальный_запрос']['коммит'],
            'исходный_коммит': сам.план['исходный_коммит'],
            'путь': сам.цели[0], 'цели': сам.цели,
            'контрольная_ветка': 'refs/heads/codex/повторный-эффект',
            'план_журнала': сам.выбор_плана}
        сам.выбор_полномочий = сам.сохранить_полномочия(сам.полномочия)

    def подготовить_базис(сам):
        """Материалы настоящих проверок входят в H до P.2 и A.3."""
        from связность_независимого_журнала import модуль_свежести
        реестр = сам.корень / 'Инструменты/реестр-системных-приложений-и-инструментов.md'
        реестр.write_text('# Инструменты\n\nСинтетическая фикстура Python и Git.\n')
        политика = сам.корень / 'Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/policy.json'
        политика.parent.mkdir(parents=True)
        политика.write_bytes(байты({'schema': 'fum.machine-local-path-policy.v2', 'exceptions': []}))
        старый = Path(сам.пример.ф.старый).relative_to('Журнал').as_posix()
        (сам.корень / 'Журнал/README.md').write_text(
            '# Журнал\n\n## Папки запросов\n\n- [Прежний запрос](' + старый + ').\n')
        результат = модуль_свежести().update_repository(сам.корень, check=False)
        if результат.errors:
            raise ValueError('; '.join(результат.errors))
        гит(сам.корень, 'add', '.')
        гит(сам.корень, 'commit', '-m', 'Закрепить лабораторный базис повторного эффекта')
        сам.исходный_коммит = гит(сам.корень, 'rev-parse', 'HEAD')
        сам.пример.вход['исходный_коммит'] = сам.исходный_коммит

    def сохранить_полномочия(сам, документ):
        выбор = сам.пример.ф.с.сохранить('Планирование/эффектные-полномочия.json', байты(документ))
        гит(сам.корень, 'branch', '-f', 'codex/повторный-эффект', выбор['коммит'])
        return выбор

    def снимок(сам):
        return сам.пример.снимок()

    def снимок_метаданных(сам):
        итог = {}
        for путь in [сам.пример.ф.с.папка, *сам.пример.ф.с.папка.rglob('*')]:
            с = путь.lstat()
            итог[str(путь)] = (с.st_dev, с.st_ino, с.st_mode, с.st_uid,
                с.st_nlink, с.st_size if путь.is_file() else None,
                с.st_mtime_ns, хэш(путь.read_bytes()) if путь.is_file() else None)
        return итог


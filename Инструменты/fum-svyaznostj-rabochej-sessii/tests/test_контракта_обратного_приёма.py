        сам.ревью['проверки'] *= 2; сам.ревью['переносимые_проверки'] *= 2
        сам.заявка['ревью_sha256'] = хэш(байты(сам.ревью))
        with сам.assertRaisesRegex(ValueError, 'повтор'):
            составить_план(сам.заявка, сам.наблюдение, байты(сам.ревью), [тест, тест])


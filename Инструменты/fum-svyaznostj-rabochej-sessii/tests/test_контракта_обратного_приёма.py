"""Контракт обратного приёма: точное дерево, независимый выбор и переносимость."""
import copy
import hashlib
import json
from pathlib import Path
import sys
import subprocess
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from контракт_обратного_приёма import составить_план


def байты(данные):
    return json.dumps(данные, ensure_ascii=False, sort_keys=True).encode()


def хэш(сырые):
    return hashlib.sha256(сырые).hexdigest()


class ОбратныйПриём(unittest.TestCase):
    def setUp(сам):
        сам.основа, сам.кандидат, сам.дерево, сам.дерево_основы = '1' * 40, '2' * 40, '3' * 40, '4' * 40
        сам.задача = '01a07d3d-d376-7ad2-aafc-67e4c25a67eb'
        сам.проверка = {'схема': 'fum.свидетельство-переносимой-проверки.1',
            'идентификатор': 'проверка-состава', 'кандидат': сам.кандидат, 'дерево': сам.дерево,
            'статус': 'успешно', 'код': 0, 'завершён': True, 'зависимости': ['дерево']}
        сам.ревью = {'схема': 'fum.решение-ревью-обратного-приёма.1',
            'координатор': сам.задача, 'основа': сам.основа, 'кандидат': сам.кандидат,
            'дерево': сам.дерево, 'разница_sha256': 'a' * 64, 'решение': 'принять',
            'охват': 'полное-изменение', 'проверки': ['проверка-состава'],
            'переносимые_проверки': ['проверка-состава']}
        сам.заявка = {'схема': 'fum.заявка-обратного-приёма.1',
            'координатор': сам.задача,
            'получатель': {'ветка': 'refs/heads/fuma', 'коммит': сам.основа, 'дерево': сам.дерево_основы},
            'источник': {'ветка': 'refs/heads/codex/proverennyij', 'коммит': сам.кандидат, 'дерево': сам.дерево},
            'ревью_sha256': '', 'проверки': []}
        сам.наблюдение = {'схема': 'fum.наблюдение-обратного-приёма.1',
            'координатор': сам.задача, 'получатель': copy.deepcopy(сам.заявка['получатель']),
            'источник': copy.deepcopy(сам.заявка['источник']), 'разница_sha256': 'a' * 64,
            'основа_является_предком': True, 'рабочее_дерево_чисто': True,
            'ревью_из_принимающего_дерева': True, 'операции_git': []}

    def вызов(сам, *, перепривязать=True):
        обзор, тест = байты(сам.ревью), байты(сам.проверка)
        if перепривязать:
            сам.заявка['ревью_sha256'] = хэш(обзор)
            сам.заявка['проверки'] = [{'идентификатор': сам.проверка['идентификатор'], 'sha256': хэш(тест)}]
        return составить_план(сам.заявка, сам.наблюдение, обзор, [тест])

    def test_план_сохраняет_два_родителя_и_дерево_кандидата(сам):
        план = сам.вызов()
        сам.assertEqual(план['родители'], [сам.основа, сам.кандидат])
        сам.assertEqual(план['дерево'], сам.дерево)
        сам.assertEqual(план['повторный_полный_прогон'], False)
        сам.assertEqual(план['разрешение_записи'], False)
        сам.assertEqual(план['ревью_sha256'], сам.заявка['ревью_sha256'])

    def test_равное_дерево_не_подменяет_коммит(сам):
        сам.наблюдение['источник']['коммит'] = '5' * 40
        with сам.assertRaisesRegex(ValueError, 'источник'):
            сам.вызов()

    def test_сдвиг_принимающей_ветки(сам):
        сам.наблюдение['получатель']['коммит'] = '6' * 40
        with сам.assertRaisesRegex(ValueError, 'получатель'):
            сам.вызов()

    def test_исходник_контракта_проходит_публикационный_сканер(сам):
        import публикационный_допуск_дочернего_состава as публикация
        корень = Path(__file__).resolve().parents[3]
        имя = 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/контракт_обратного_приёма.py'
        данные = {имя: (корень / имя).read_bytes()}
        исходники = {ключ: публикация.прочитать_код(корень / путь)
                     for ключ, путь in публикация.ИСХОДНИКИ_СКАНЕРА}
        политика = публикация.разобрать((корень / публикация.ПОЛИТИКА).read_bytes())
        with публикация.сканер(исходники) as сканер:
            результат = публикация.сканировать(сканер, данные, [имя], политика)
        сам.assertEqual(результат['код'], 0, результат['находки'])

    def test_недопустимый_символ_DEL_в_имени_ветки(сам):
        for имя in ('получатель', 'источник'):
            with сам.subTest(имя=имя):
                старое = сам.заявка[имя]['ветка']
                сам.заявка[имя]['ветка'] = 'refs/heads/x\x7f'
                сам.наблюдение[имя]['ветка'] = 'refs/heads/x\x7f'
                try:
                    with сам.assertRaises(ValueError): сам.вызов()
                finally:
                    сам.заявка[имя]['ветка'] = старое
                    сам.наблюдение[имя]['ветка'] = старое


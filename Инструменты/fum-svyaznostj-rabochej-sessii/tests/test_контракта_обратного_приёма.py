    def test_cli_повтор_и_отказ_без_изменения_входов(сам):
        ожидаемый = сам.вызов()
        with tempfile.TemporaryDirectory() as каталог:
            корень = Path(каталог)
            команда = [sys.executable, '-E', '-s', '-S', '-B',
                str(Path(__file__).resolve().parents[1] / 'scripts' / 'проверить-обратный-приём.py')]
            for имя, объект in (('заявка', сам.заявка), ('наблюдение', сам.наблюдение),
                                ('ревью', сам.ревью), ('проверка', сам.проверка)):
                путь = корень / (имя + '.json')
                путь.write_bytes(байты(объект))
                команда.extend(['--' + имя, str(путь)])
            до = {п.name: п.read_bytes() for п in корень.iterdir()}
            for _ in range(2):
                результат = subprocess.run(команда, cwd=корень, capture_output=True, timeout=10)
                сам.assertEqual(результат.returncode, 0, результат.stderr)
                сам.assertEqual(json.loads(результат.stdout), ожидаемый)
                сам.assertEqual(результат.stderr, b'')
                сам.assertEqual({п.name: п.read_bytes() for п in корень.iterdir()}, до)
            for сырые in (байты(сам.заявка)[:-1] + ', "проверки": []}'.encode(), b'{"x":NaN}'):
                (корень / 'заявка.json').write_bytes(сырые)
                до['заявка.json'] = сырые
                результат = subprocess.run(команда, cwd=корень, capture_output=True, timeout=10)
                сам.assertEqual(результат.returncode, 2)
                сам.assertEqual(результат.stdout, b'')
                сам.assertIs(json.loads(результат.stderr)['разрешение_записи'], False)
                сам.assertEqual({п.name: п.read_bytes() for п in корень.iterdir()}, до)



"""Три свежих CLI-процесса на одном конечном синтетическом Git-корпусе."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tempfile
import time

from test_построителя_дерева_базиса_узла import (
    ПримерПостроителя, ожидаемое_дерево, снимок, штатный_гит, базис)

КОРЕНЬ = Path(__file__).resolve().parents[3]
ИСПОЛНИТЕЛЬ = КОРЕНЬ / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/построить_дерево_базиса_узла.py'
СОСТАВ = [ИСПОЛНИТЕЛЬ, Path(базис.__file__), Path(__file__),
    Path(__file__).with_name('test_построителя_дерева_базиса_узла.py'),
    Path(__file__).with_name('test_приёма_базиса_состояния_узла.py')]


def сохранить(путь, данные):
    with путь.open('xb') as поток: поток.write(данные)
    путь.chmod(0o400)
    return {'байты': len(данные), 'sha256': hashlib.sha256(данные).hexdigest()}


def измерить(каталог):
    базис.требовать(каталог.is_absolute() and каталог == каталог.resolve()
        and not каталог.exists() and каталог.parent.is_dir()
        and not каталог.is_relative_to(КОРЕНЬ)
        and not any(os.path.lexists(п / '.git') for п in [каталог, *каталог.parents]),
        'RAW требует нового физического каталога вне Git')
    каталог.mkdir(mode=0o700)
    код = {str(п.relative_to(КОРЕНЬ)): базис.хэш(п.read_bytes()) for п in СОСТАВ}
    записи = []
    with tempfile.TemporaryDirectory(prefix='fum-builder-profile-', dir=каталог) as временный:
        пример = ПримерПостроителя(временный)
        пример.пересечение()
        ожидаемый = ожидаемое_дерево(пример.корень, пример.ожидаемые(), пример.эталонные_объекты)
        вход = Path(временный) / 'вход.json'
        выбор = Path(временный) / 'выбор.json'
        сохранить(вход, базис.байты(пример.вход))
        сохранить(выбор, базис.байты(пример.выбор))
        исходный = снимок(пример.корень)
        закреплённый = {'K': пример.вход['K'], 'R': пример.вход['R'],
            'вход_sha256': базис.хэш(вход.read_bytes()), 'выбор': пример.выбор,
            'источник_sha256': базис.хэш(базис.байты(исходный)), 'ожидаемое_дерево': ожидаемый}
        результат_до = None
        for номер in range(1, 4):
            # Только созданное этим измерителем хранилище собственной фикстуры.
            базис.требовать(снимок(пример.корень) == исходный, 'дрейф источника профиля')
            базис.требовать(пример.объекты.parent == Path(временный).resolve()
                and not пример.объекты.is_symlink(), 'подменён каталог фикстуры')
            shutil.rmtree(пример.объекты)
            пример.объекты.mkdir(mode=0o700)
            повтор = каталог / str(номер)
            повтор.mkdir(mode=0o700)
            начало = time.monotonic_ns()
            код_процесса = None
            ошибка_процесса = None
            try:
                процесс = subprocess.run([sys.executable, '-B', str(ИСПОЛНИТЕЛЬ),
                    '--вход', str(вход.resolve()), '--выбранные-решения', str(выбор.resolve()), '--профиль'],
                    capture_output=True, env=базис.среда_гит(), timeout=120)
                наружу, диагностика = процесс.stdout, процесс.stderr
                код_процесса = процесс.returncode
            except subprocess.TimeoutExpired as ошибка:
                наружу, диагностика = ошибка.stdout or b'', ошибка.stderr or b''
                ошибка_процесса = 'тайм-аут'
            внешнее = time.monotonic_ns() - начало
            каналы = {'stdout': сохранить(повтор / 'stdout.bin', наружу),
                'stderr': сохранить(повтор / 'stderr.bin', диагностика)}
            сохранить(повтор / 'исход.json', базис.байты({'код': код_процесса,
                'ошибка': ошибка_процесса, 'внешнее_нс': внешнее, 'каналы': каналы}))
            базис.требовать(код_процесса == 0, 'свежий процесс отказал; его RAW сохранён')
            результат, профиль = базис.разобрать(наружу), базис.разобрать(диагностика)
            базис.требовать(результат['дерево'] == ожидаемый
                and (результат_до is None or результат_до == наружу), 'дрейф кандидата профиля')
            базис.требовать(снимок(пример.корень) == исходный, 'профиль изменил источник')
            базис.требовать(базис.хэш(вход.read_bytes()) == закреплённый['вход_sha256']
                and базис.разобрать(выбор.read_bytes()) == закреплённый['выбор'], 'дрейф входа профиля')
            результат_до = наружу
            записи.append({'повтор': номер, 'код': код_процесса, 'внешний_процесс_нс': внешнее,
                'фазы': профиль, 'каналы': каналы, 'источник_сохранён': True})
        версия_гит = штатный_гит(пример.корень, '--version').decode().strip()
    базис.требовать(код == {str(п.relative_to(КОРЕНЬ)): базис.хэш(п.read_bytes()) for п in СОСТАВ},
        'код измерителя изменился')
    исполняемые = {имя: базис.хэш(Path(путь).resolve().read_bytes()) for имя, путь in
        [('Python', sys.executable), ('Git', shutil.which('git'))]}
    return {'схема': 'fum.профиль-построителя-дерева-базиса.1', 'корпус': закреплённый,
        'код': код, 'исполняемые': исполняемые, 'Python': platform.python_version(),
        'Git': версия_гит, 'платформа': platform.platform(), 'повторы': записи,
        'граница': {'синтетический_корпус': True, 'свежих_процессов': 3,
            'подготовка_фикстуры_и_эталона_исключена': True,
            'начальное_собственное_хранилище_каждый_раз_пусто': True,
            'полное_замыкание_системных_библиотек': False,
            'настоящий_B_и_Creator_не_измерены': True}}


def главный():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--каталог-raw', type=Path, required=True)
    разбор.add_argument('--выход', type=Path, required=True)
    параметры = разбор.parse_args()
    try:
        результат = измерить(параметры.каталог_raw)
        сохранить(параметры.выход, базис.байты(результат))
        print(базис.байты(результат).decode(), end='')
        return 0
    except (ValueError, OSError, subprocess.SubprocessError) as ошибка:
        print(str(ошибка), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(главный())

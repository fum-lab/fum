"""Закреплённое обычное поручение: настоящий Git и нативный префикс."""
import hashlib
import importlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

СКРИПТЫ = Path(__file__).resolve().parents[1] / 'scripts'
sys.path.insert(0, str(СКРИПТЫ))
ЖУРНАЛ = 'Журнал/2026-10-01_00-00-00_MSK_проверить-поручение'


class ОбычноеПоручение(unittest.TestCase):
    def setUp(сам):
        сам.подготовить_фикстуру()

    def подготовить_фикстуру(сам):
        сам.модуль = importlib.import_module('обычное_поручение')
        сам.временный_каталог = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный_каталог.cleanup)
        сам.основание = Path(сам.временный_каталог.name).resolve()
        сам.корень = сам.основание / 'repo'
        сам.корень.mkdir()
        сам.корневая_задача = '01a07d3d-d376-7ad2-aafc-67e4c25a67eb'
        сам.исполнитель = '01a0f40a-a34f-7950-b74c-2e8b942cfdcb'
        сам.ветка = 'refs/heads/codex/тест-поручения'
        сам.гит('init', '-q', '-b', 'codex/тест-поручения')
        сам.гит('config', 'user.name', 'FUM Test')
        сам.гит('config', 'user.email', 'test@example.invalid')
        файл_постановки = сам.корень / 'Планирование/постановка.md'
        файл_постановки.parent.mkdir()
        файл_постановки.write_text('Проверяемое поручение.\n')
        сам.гит('add', '.')
        сам.гит('commit', '-qm', 'Постановка')
        сам.начальный_коммит = сам.гит('rev-parse', 'HEAD').strip()
        сам.текст_поручения = 'Прочитай закреплённую постановку и выполни ограниченный результат.\n'
        сам.нативный_файл = сам.основание / 'native.jsonl'
        сам.записи = [
            {'type': 'session_meta', 'payload': {'id': сам.исполнитель, 'cwd': str(сам.корень),
                'thread_source': 'agent_created_thread', 'git': {'commit_hash': сам.начальный_коммит}}},
            {'type': 'turn_context', 'payload': {'cwd': str(сам.корень), 'model': 'gpt-6.1-sol', 'effort': 'ultra'}},
            {'type': 'response_item', 'payload': {'type': 'function_call_output', 'name': 'create_thread',
                'output': '<codex_delegation>\n  <source_thread_id>' + сам.корневая_задача +
                '</source_thread_id>\n  <input>' + сам.текст_поручения + '</input>\n</codex_delegation>'}},
        ]
        сам.сохранить_нативный()
        сам.акт = {'схема': 'fum.поручение-дочерней-контрольной-точки.1',
            'координатор': сам.корневая_задача, 'исполнитель': сам.исполнитель, 'ветка': сам.ветка,
            'область': ['Компонент/', ЖУРНАЛ + '/', 'Индексы/состав.md'],
            'постановка': {'коммит': сам.начальный_коммит, 'путь': 'Планирование/постановка.md',
                'sha256': hashlib.sha256(файл_постановки.read_bytes()).hexdigest()},
            'хэш_нативного_поручения': hashlib.sha256(сам.текст_поручения.encode()).hexdigest()}
        сам.сохранить_акт()
        сам.параметры = {'схема': 'fum.создание-коммита.7', 'режим': 'контрольная-точка',
            'задача': сам.корневая_задача, 'исполнитель': сам.исполнитель, 'корень': str(сам.корень),
            'ветка': сам.ветка, 'исходный_коммит': сам.гит('rev-parse', 'HEAD').strip(),
            'источник_модели': str(сам.нативный_файл), 'выбранное_поручение': сам.выбор,
            'запрос': ЖУРНАЛ + '/запрос.md', 'история_модели': ЖУРНАЛ + '/материалы/модель.json',
            'разрешённые_цели': ['Компонент/новый.swift', ЖУРНАЛ + '/запрос.md',
                ЖУРНАЛ + '/отчёт.md', ЖУРНАЛ + '/материалы/модель.json']}
        сам.среда = patch.dict(os.environ, {'CODEX_THREAD_ID': сам.исполнитель})
        сам.среда.start()
        сам.addCleanup(сам.среда.stop)

    def гит(сам, *аргументы_гита):
        return subprocess.check_output(['git', '-C', str(сам.корень), *аргументы_гита], stderr=subprocess.PIPE).decode()

    def сохранить_нативный(сам):
        сам.нативный_файл.write_text(''.join(json.dumps(элемент, ensure_ascii=False) + '\n' for элемент in сам.записи))

    def сохранить_акт(сам):
        путь = сам.корень / 'Планирование/поручение.json'
        путь.write_text(json.dumps(сам.акт, ensure_ascii=False) + '\n')
        сам.гит('add', '.')
        сам.гит('commit', '-qm', 'Закрепить обычного исполнителя')
        сам.выбор = {'координатор': сам.корневая_задача, 'исполнитель': сам.исполнитель,
            'коммит': сам.гит('rev-parse', 'HEAD').strip(), 'путь': 'Планирование/поручение.json',
            'sha256': hashlib.sha256(путь.read_bytes()).hexdigest()}

    def вызвать_читатель(сам, выбор=None):
        return сам.модуль.проверить(сам.параметры, сам.выбор if выбор is None else выбор)

    def отказ(сам, действие):
        вершина = сам.гит('rev-parse', 'HEAD')
        индекс = (сам.корень / '.git/index').read_bytes()
        файлы = sorted(str(элемент.relative_to(сам.основание)) for элемент in сам.основание.rglob('*') if элемент.is_file())
        with сам.assertRaises(ValueError):
            действие()
        сам.assertEqual(сам.гит('rev-parse', 'HEAD'), вершина)
        сам.assertEqual((сам.корень / '.git/index').read_bytes(), индекс)
        сам.assertEqual(sorted(str(элемент.relative_to(сам.основание)) for элемент in сам.основание.rglob('*') if элемент.is_file()), файлы)

    def test_раздельные_идентичности_и_новые_пути_проверяются_без_записи(сам):
        до = (сам.корень / '.git/index').read_bytes()
        результат = сам.вызвать_читатель()
        сам.assertEqual(результат['выбранное_поручение'], сам.выбор)
        сам.assertEqual(результат['нативное_начало']['sha256'], hashlib.sha256(
            ''.join(json.dumps(элемент, ensure_ascii=False) + '\n' for элемент in сам.записи[:2]).encode()).hexdigest())
        сам.assertEqual((сам.корень / '.git/index').read_bytes(), до)
        сам.assertFalse((сам.корень / 'Журнал').exists())

    def test_копия_выбора_не_заменяет_независимый_вход(сам):
        сам.отказ(lambda: сам.модуль.проверить(сам.параметры, None))
        неверный = dict(сам.выбор, sha256='0' * 64)
        сам.отказ(lambda: сам.вызвать_читатель(неверный))

    def test_чужое_нативное_начало_и_отправитель_не_допускаются(сам):
        for поле, значение in [('id', сам.корневая_задача), ('cwd', str(сам.основание)),
                ('thread_source', 'subagent')]:
            прежний = сам.записи[0]['payload'][поле]
            сам.записи[0]['payload'][поле] = значение
            сам.сохранить_нативный()
            сам.отказ(сам.вызвать_читатель)
            сам.записи[0]['payload'][поле] = прежний
        сам.сохранить_нативный()
        сам.записи[2]['payload']['output'] = сам.записи[2]['payload']['output'].replace(
            сам.корневая_задача, сам.исполнитель)
        сам.сохранить_нативный()
        сам.отказ(сам.вызвать_читатель)

    def test_расширение_области_и_символическая_ссылка_дают_отказ(сам):
        for имя in ['README.md', 'Компонент/../чужой.swift', 'Компонент//новый.swift']:
            сам.параметры['разрешённые_цели'].append(имя)
            сам.отказ(сам.вызвать_читатель)
            сам.параметры['разрешённые_цели'].pop()
        (сам.корень / 'Компонент').symlink_to(сам.основание, target_is_directory=True)
        сам.отказ(сам.вызвать_читатель)

    def test_подмена_закреплённой_постановки_отклоняется(сам):
        сам.акт['постановка']['sha256'] = '0' * 64
        сам.сохранить_акт()
        сам.параметры.update(выбранное_поручение=сам.выбор,
            исходный_коммит=сам.гит('rev-parse', 'HEAD').strip())
        сам.отказ(сам.вызвать_читатель)

    def test_новая_семантика_не_применяется_к_старой_схеме(сам):
        for схема in ['fum.создание-коммита.2', 'fum.создание-коммита.5',
                'fum.создание-коммита.6', 'fum.создание-коммита.3']:
            сам.параметры['схема'] = схема
            сам.отказ(сам.вызвать_читатель)

    def test_ссылка_гита_или_символическая_ссылка_не_заменяет_акт(сам):
        путь_акта = сам.корень / сам.выбор['путь']
        оригинал = путь_акта.read_bytes()
        путь_акта.unlink()
        путь_акта.symlink_to('постановка.md')
        сам.гит('add', '.')
        сам.гит('commit', '-qm', 'Подменить тип акта')
        сам.выбор['коммит'] = сам.гит('rev-parse', 'HEAD').strip()
        сам.выбор['sha256'] = hashlib.sha256('постановка.md'.encode()).hexdigest()
        сам.параметры.update(выбранное_поручение=сам.выбор, исходный_коммит=сам.выбор['коммит'])
        сам.отказ(сам.вызвать_читатель)
        путь_акта.unlink()
        путь_акта.write_bytes(оригинал)
        сам.гит('update-index', '--cacheinfo', '160000,' + сам.начальный_коммит + ',' + сам.выбор['путь'])
        сам.гит('commit', '-qm', 'Подменить акт gitlink')
        сам.выбор['коммит'] = сам.гит('rev-parse', 'HEAD').strip()
        сам.параметры['исходный_коммит'] = сам.выбор['коммит']
        сам.отказ(сам.вызвать_читатель)

    def test_позднее_поручение_и_первичный_хэш_отклоняются(сам):
        сам.записи.insert(2, {'type': 'response_item', 'payload': {
            'type': 'message', 'role': 'assistant', 'content': [{'type': 'output_text', 'text': 'Начал'}]}})
        сам.сохранить_нативный()
        сам.отказ(сам.вызвать_читатель)
        сам.записи.pop(2)
        сам.записи[2]['payload']['output'] = сам.записи[2]['payload']['output'].replace(
            сам.текст_поручения, сам.текст_поручения + 'Изменено')
        сам.сохранить_нативный()
        сам.отказ(сам.вызвать_читатель)

    def test_широкая_скрытая_область_и_корневая_среда_отклоняются(сам):
        with patch.dict(os.environ, {'CODEX_THREAD_ID': сам.корневая_задача}):
            сам.отказ(сам.вызвать_читатель)
        for область in ['Журнал/', 'Proyekcii/', '.git/config']:
            сам.акт['область'].append(область)
            сам.сохранить_акт()
            сам.параметры.update(выбранное_поручение=сам.выбор,
                исходный_коммит=сам.гит('rev-parse', 'HEAD').strip())
            сам.отказ(сам.вызвать_читатель)
            сам.акт['область'].pop()

    def test_повторное_чтение_замечает_изменение_нативного_префикса(сам):
        прежний = сам.вызвать_читатель()
        сам.нативный_файл.write_text(сам.нативный_файл.read_text().replace(сам.текст_поручения.rstrip(), 'Другой текст'))
        сам.отказ(сам.вызвать_читатель)
        сам.сохранить_нативный()
        сам.assertEqual(сам.вызвать_читатель(), прежний)

    def test_регистр_существующего_каталога_не_является_алиасом(сам):
        (сам.корень / 'компонент').mkdir()
        сам.отказ(сам.вызвать_читатель)

    def test_подмена_между_двумя_нативными_чтениями_даёт_отказ(сам):
        читатель = сам.модуль.постановка.прочитать_нативное_поручение
        def подменить(*аргументы, **именованные):
            сам.записи[0]['payload']['id'] = сам.корневая_задача
            сам.сохранить_нативный()
            return читатель(*аргументы, **именованные)
        with patch.object(сам.модуль.постановка, 'прочитать_нативное_поручение', подменить):
            сам.отказ(сам.вызвать_читатель)

    def test_журнал_не_принимает_вложенный_чужой_запрос(сам):
        сам.параметры['запрос'] = ЖУРНАЛ + '/чужой/запрос.md'
        сам.отказ(сам.вызвать_читатель)

    def test_история_модели_принадлежит_материалам_своего_этапа(сам):
        сам.параметры['история_модели'] = 'Компонент/модель.json'
        сам.отказ(сам.вызвать_читатель)


if __name__ == '__main__':
    unittest.main()

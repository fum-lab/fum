    def test_поздний_ACT_принимает_историю_но_требует_свежий_LIVE(сам):
        _, помощник, пример, состав, вход, сохранено = сам.стенд()
        план, файл = сам.план(пример, состав, вход, сохранено)
        итог = сам.применить(пример, состав, вход, сохранено, файл)
        старое = пример.решение['координация']
        try:
            пример.решение['координация'] = сохранено['обзор']['координация']
            акт = помощник.поздний_обзор(пример, вход,
                {'эффективная_область': план['свидетельство']['эффективная_область']}, итог['свидетельство'])
        finally:
            пример.решение['координация'] = старое
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=акт['писатель']):
            результат = пример.м.построить_план(акт, выбранный_состав=состав)
        сам.assertEqual(результат['фаза'], 'акт')
        сам.assertEqual(результат['схема'], 'fum.план-подготовки-дочернего-поручения.4')
        with Path(акт['живой_источник']).open('ab') as поток:
            поток.write(примеры.байты(примеры.сообщение('Новое ограничение человека.', 101)))
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=акт['писатель']), сам.assertRaises(ValueError):
            пример.м.построить_план(акт, выбранный_состав=состав)



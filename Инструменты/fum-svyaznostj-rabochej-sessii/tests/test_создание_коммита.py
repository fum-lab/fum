    def гит(сам, *аргументы):
        return subprocess.check_output(["git", "-C", str(сам.корень), *аргументы], text=True, stderr=subprocess.PIPE)

    def записать_источник(сам):
        сам.источник.write_text("".join(json.dumps(запись, ensure_ascii=False) + "\n" for запись in сам.события))

    def готовить(сам):
        коммит.подготовить(сам.параметры)
        сам.гит("add", ".")
        with contextlib.redirect_stdout(io.StringIO()):
            код = сам.отчёты.выполнить_запуск(сам.корень, сам.запрос, "Проверить байты фикстуры", "фикстура", ЗАПУСК, 15,
                [sys.executable, "-c", "from pathlib import Path; assert Path('данные.txt').read_text() == 'проверено\\n'"],
                класс_проверки="адресная", приёмочные_раунды=True)
            сам.assertEqual(0, код)
            сам.отчёты.выполнить_предпросмотр(сам.корень, сам.запрос)
        сам.гит("add", str(Path(ЗАПРОС).parent))

    def создать(сам):
        return коммит.создать(Path(сам.параметры["подготовка"]), [ЗАПУСК])

    def отказ_без_коммита(сам, действие):
        голова = сам.гит("rev-parse", "HEAD")
        индекс = сам.гит("ls-files", "--stage")
        with сам.assertRaises(коммит.ОшибкаКоммита):
            действие()
        сам.assertEqual(голова, сам.гит("rev-parse", "HEAD"))
        сам.assertEqual(индекс, сам.гит("ls-files", "--stage"))

    def test_реальный_коммит_и_повтор_возвращают_один_объект(сам):
        сам.готовить()
        итог = сам.создать()
        сам.assertEqual(итог["коммит"], сам.гит("rev-parse", "HEAD").strip())
        сырой = сам.гит("cat-file", "commit", итог["коммит"])
        сам.assertIn("author FUM Codex [gpt-6-astra; effort=ultra] <fixture@example.invalid>", сырой)
        сам.assertIn("committer FUM <fixture@example.invalid>", сырой)
        сам.assertIn(КОМАНДА, сырой)
        сам.assertIn("model: gpt-6-astra\neffort: ultra", сырой)
        сам.assertTrue(сырой.endswith("Codex-Thread-ID: " + ЗАДАЧА + "\n"))
        сам.assertEqual([сам.начало], итог["родители"])
        сам.assertEqual(итог["коммит"], сам.создать()["коммит"])

    def test_настоящее_слияние_сохраняет_порядок_обоих_родителей(сам):
        сам.гит("checkout", "-qb", "codex/источник")
        (сам.корень / "вклад.txt").write_text("вклад\n")
        сам.гит("add", "вклад.txt")
        сам.гит("commit", "-qm", "Внешняя фикстура")
        второй = сам.гит("rev-parse", "HEAD").strip()
        сам.гит("checkout", "-q", "codex/фикстура")
        сам.гит("merge", "--no-ff", "--no-commit", второй)
        сам.параметры["родители"].append(второй)
        сам.запрос.write_text(сам.запрос.read_text() + "- [Вклад](../../вклад.txt).\n")
        сам.готовить()
        итог = сам.создать()
        сам.assertEqual([сам.начало, второй], итог["родители"])
        сам.assertEqual(" ".join(итог["родители"]), сам.гит("show", "-s", "--format=%P", итог["коммит"]).strip())


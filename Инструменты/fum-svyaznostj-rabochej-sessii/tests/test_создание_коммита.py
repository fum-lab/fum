"""Реальные Git, первичный JSONL и отчётные допуски без сети и заглушек успеха."""
import contextlib
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import unittest
from unittest import mock

СКРИПТЫ = Path(__file__).resolve().parents[1] / "scripts"
sys.path.insert(0, str(СКРИПТЫ))
import создание_коммита as коммит
from сообщения_задачи import прочитать_сообщения

ЗАДАЧА = "00000000-0000-0000-0000-000000000001"
ЗАПУСК = "00000000-0000-0000-0000-000000000002"
ЗАПРОС = "Журнал/2026-09-15_23-00-00_MSK_проверить-коммит/запрос.md"
КОМАНДА = "Сохрани точный результат.\n"


class СозданиеКоммита(unittest.TestCase):
    def setUp(сам):
        временный = tempfile.TemporaryDirectory()
        сам.addCleanup(временный.cleanup)
        сам.каталог = Path(временный.name).resolve()
        сам.корень = сам.каталог / "репозиторий"
        сам.корень.mkdir()
        # Изоляция фикстуры от identity, подписей и hooks пользовательской машины.
        среда = {ключ: значение for ключ, значение in os.environ.items() if not ключ.startswith("GIT_")}
        среда.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull, CODEX_THREAD_ID=ЗАДАЧА)
        сам.среда = mock.patch.dict(os.environ, среда, clear=True)
        сам.среда.start()
        сам.addCleanup(сам.среда.stop)
        сам.гит("init", "-q", "-b", "codex/фикстура")
        сам.гит("config", "user.name", "FUM")
        сам.гит("config", "user.email", "fixture@example.invalid")
        (сам.корень / "данные.txt").write_text("исходное\n")
        сам.гит("add", ".")
        сам.гит("commit", "-qm", "Исходная фикстура")
        сам.начало = сам.гит("rev-parse", "HEAD").strip()
        сам.источник = сам.каталог / "native.jsonl"
        сам.события = [
            {"type": "session_meta", "payload": {"id": ЗАДАЧА}},
            {"type": "turn_context", "timestamp": "2026-09-15T20:00:00Z", "payload": {"model": "gpt-6-astra", "effort": "ultra"}},
            {"type": "response_item", "payload": {"type": "message", "role": "user", "content": [{"type": "input_text", "text": КОМАНДА}], "internal_chat_message_metadata_passthrough": {"content_item_kinds": ["user.text"]}}},
        ]
        сам.записать_источник()
        первичные = прочитать_сообщения(сам.источник, ЗАДАЧА, корень_репозитория=сам.корень, без_записи=True)
        сам.экземпляр = первичные["сообщения"][0]["экземпляр"]
        сам.запрос = сам.корень / ЗАПРОС
        сам.запрос.parent.mkdir(parents=True)
        (сам.запрос.parent / "материалы").mkdir()
        сам.запрос.write_text(
            "# Исходный запрос 2026-09-15 23:00:00 MSK - Проверить коммит\n\n"
            "## Навигация по запросам\n\n- Предыдущий запрос: нет\n- Следующий запрос: нет\n\n"
            "## Текст запроса\n\n````text\n" + КОМАНДА + "\n````\n\n"
            "## Идентификатор сеанса Codex\n\nCodex-Thread-ID: " + ЗАДАЧА + "\n\n"
            "## Использованные инструменты\n\n- Python 3; Git; [реестр](../../Инструменты/реестр-системных-приложений-и-инструментов.md).\n"
            "- fum-moskovskoye-vremya-rabochej-sessii; наблюдения модели хранятся отдельно.\n\n"
            "## Проверки\n\nТочные байты проверяет отдельный процесс.\n\n"
            "## Повлиял на файлы\n\n- [Данные](../../данные.txt).\n- [Журнал](../).\n"
            "- [Запрос](запрос.md).\n- [Отчёт](отчёт.md).\n- [Инструменты](../../Инструменты/).\n")
        (сам.корень / "Журнал/README.md").write_text("# Журнал\n\nПроверка.\n\n## Папки запросов\n\n- [Запрос](2026-09-15_23-00-00_MSK_проверить-коммит/отчёт.md).\n")
        (сам.корень / "Инструменты").mkdir()
        (сам.корень / "Инструменты/реестр-системных-приложений-и-инструментов.md").write_text("# Инструменты\n\nСинтетическая фикстура Python и Git.\n")
        сам.отчёты = коммит.отчёты
        сам.запрос.with_name("отчёт.md").write_text(
            "# Отчёт 2026-09-15 23:00:00 MSK - Проверить коммит\n\nПроверяется контракт создания.\n\n"
            "## Профиль времени выполнения\n\n"
            "| Стадия | Длительность | Границы и способ измерения |\n"
            "| ------ | ------------ | ------------------------- |\n"
            "| Подготовка | не измерено | Фикстура |\n| Проверка | не измерено | Отдельный процесс |\n\n"
            "Граница профиля: синтетическая фикстура; полезная работа FUM не измеряется.\n\n"
            "### Прямые запуски проверок\n\n" + сам.отчёты.ОТКРЫТЫЙ_МАРКЕР + "\nДо запуска.\n" + сам.отчёты.КОНЕЧНЫЙ_МАРКЕР + "\n\n## Источники\n\n[Запрос](запрос.md).\n")
        (сам.корень / "данные.txt").write_text("проверено\n")
        сам.параметры = {
            "схема": "fum.создание-коммита.1", "корень": str(сам.корень),
            "ветка": "refs/heads/codex/фикстура", "исходный_коммит": сам.начало,
            "родители": [сам.начало], "задача": ЗАДАЧА, "имя_автора": "FUM Интегратор",
            "запрос": ЗАПРОС, "источник_модели": str(сам.источник),
            "кэш_модели": str(сам.каталог / "модель-курсор.json"),
            "история_модели": str(Path(ЗАПРОС).parent / "материалы/история-модели.json"),
            "источники": [{"путь": str(сам.источник), "задача": ЗАДАЧА, "экземпляры": [сам.экземпляр]}],
            "заголовок": "Проверить точное создание коммита", "описание": "Сохранены проверенные байты.",
            "сообщение": str(сам.каталог / "сообщение.txt"),
            "подготовка": str(сам.каталог / "подготовка.json"),
            "квитанция": str(сам.каталог / "квитанция.json"), "режим": "контрольная-точка",
        }

    def гит(сам, *аргументы):
        return subprocess.check_output(["git", "-C", str(сам.корень), *аргументы], text=True, stderr=subprocess.PIPE)

    def записать_источник(сам):
        сам.источник.write_text("".join(json.dumps(запись, ensure_ascii=False) + "\n" for запись in сам.события))

    def готовить(сам):
        коммит.подготовить(сам.параметры)
        сам.гит("add", ".")
        with contextlib.redirect_stdout(io.StringIO()):
            код = сам.отчёты.выполнить_запуск(сам.корень, сам.запрос, "Проверить байты фикстуры", "фикстура", ЗАПУСК, 15,
                [sys.executable, "-c", "from pathlib import Path; assert Path('данные.txt').read_text() == 'проверено\\n'"],
                класс_проверки="адресная", приёмочные_раунды=True)
            сам.assertEqual(0, код)
            сам.отчёты.выполнить_предпросмотр(сам.корень, сам.запрос)
        сам.гит("add", str(Path(ЗАПРОС).parent))

    def создать(сам):
        return коммит.создать(Path(сам.параметры["подготовка"]), [ЗАПУСК])

    def отказ_без_коммита(сам, действие):
        голова = сам.гит("rev-parse", "HEAD")
        индекс = сам.гит("ls-files", "--stage")
        with сам.assertRaises(коммит.ОшибкаКоммита):
            действие()
        сам.assertEqual(голова, сам.гит("rev-parse", "HEAD"))
        сам.assertEqual(индекс, сам.гит("ls-files", "--stage"))

    def test_реальный_коммит_и_повтор_возвращают_один_объект(сам):
        сам.готовить()
        итог = сам.создать()
        сам.assertEqual(итог["коммит"], сам.гит("rev-parse", "HEAD").strip())
        сырой = сам.гит("cat-file", "commit", итог["коммит"])
        сам.assertIn("author FUM Интегратор <fixture@example.invalid>", сырой)
        сам.assertIn("committer FUM <fixture@example.invalid>", сырой)
        сам.assertIn(КОМАНДА, сырой)
        сам.assertIn("model: gpt-6-astra\neffort: ultra", сырой)
        сам.assertTrue(сырой.endswith("Codex-Thread-ID: " + ЗАДАЧА + "\n"))
        сам.assertEqual([сам.начало], итог["родители"])
        сам.assertEqual(итог["коммит"], сам.создать()["коммит"])

    def test_настоящее_слияние_сохраняет_порядок_обоих_родителей(сам):
        сам.гит("checkout", "-qb", "codex/источник")
        (сам.корень / "вклад.txt").write_text("вклад\n")
        сам.гит("add", "вклад.txt")
        сам.гит("commit", "-qm", "Внешняя фикстура")
        второй = сам.гит("rev-parse", "HEAD").strip()
        сам.гит("checkout", "-q", "codex/фикстура")
        сам.гит("merge", "--no-ff", "--no-commit", второй)
        сам.параметры["родители"].append(второй)
        сам.запрос.write_text(сам.запрос.read_text() + "- [Вклад](../../вклад.txt).\n")
        сам.готовить()
        итог = сам.создать()
        сам.assertEqual([сам.начало, второй], итог["родители"])
        сам.assertEqual(" ".join(итог["родители"]), сам.гит("show", "-s", "--format=%P", итог["коммит"]).strip())

    def test_неверные_адрес_роль_и_родители_отказывают(сам):
        случаи = [("имя_автора", имя) for имя in ("FUMИнтегратор", "FUM  Интегратор", "FUM\u00a0Интегратор", "FUM интегратор")]
        случаи += [("ветка", "refs/heads/codex/другая"), ("исходный_коммит", "0" * 40), ("родители", [сам.начало, сам.начало])]
        for поле, значение in случаи:
            with сам.subTest(поле=поле, значение=значение):
                сам.отказ_без_коммита(lambda: коммит.подготовить({**сам.параметры, поле: значение}))

    def test_неизвестная_модель_и_ложный_экземпляр_не_дают_сообщения(сам):
        сам.события[1]["payload"].pop("effort")
        сам.записать_источник()
        сам.отказ_без_коммита(lambda: коммит.подготовить(сам.параметры))
        сам.assertFalse(Path(сам.параметры["сообщение"]).exists())

    def test_изменённые_сообщение_модель_и_проверенный_вход_отказывают(сам):
        сам.готовить()
        сообщение = Path(сам.параметры["сообщение"])
        прежнее = сообщение.read_bytes()
        сообщение.write_bytes(прежнее.replace(КОМАНДА.encode(), b"changed\n"))
        сам.отказ_без_коммита(сам.создать)
        сообщение.write_bytes(прежнее)
        (сам.корень / "данные.txt").write_text("другое\n")
        сам.отказ_без_коммита(сам.создать)
        сам.гит("add", "данные.txt")
        сам.отказ_без_коммита(сам.создать)

    def test_скрытый_индекс_и_подмена_источника_отказывают(сам):
        сам.готовить()
        сам.гит("update-index", "--assume-unchanged", "данные.txt")
        сам.отказ_без_коммита(сам.создать)
        сам.гит("update-index", "--no-assume-unchanged", "данные.txt")
        сам.события[2]["payload"]["content"][0]["text"] = "Другая команда.\n"
        сам.записать_источник()
        сам.отказ_без_коммита(сам.создать)

    def test_нет_применимой_проверки_нет_коммита(сам):
        сам.готовить()
        сам.отказ_без_коммита(lambda: коммит.создать(Path(сам.параметры["подготовка"]), []))
        сам.отказ_без_коммита(lambda: коммит.создать(Path(сам.параметры["подготовка"]), [ЗАДАЧА]))

    def test_перенаправление_гита_и_чужой_идентификатор_отказывают(сам):
        with mock.patch.dict(os.environ, {"GIT_INDEX_FILE": str(сам.каталог / "чужой-индекс")}):
            with сам.assertRaises(коммит.ОшибкаКоммита):
                коммит.подготовить(сам.параметры)
        сам.параметры["описание"] += "\nCodex-Thread-ID: " + ЗАПУСК
        сам.отказ_без_коммита(lambda: коммит.подготовить(сам.параметры))

    def test_отказ_гита_сохраняет_квитанцию_и_не_повторяет_вызов(сам):
        сам.готовить()
        крючок = сам.корень / ".git/hooks/pre-commit"
        крючок.write_text("#!/bin/sh\nexit 1\n")
        крючок.chmod(0o755)
        сам.отказ_без_коммита(сам.создать)
        сам.assertTrue(Path(сам.параметры["квитанция"]).is_file())
        квитанция = json.loads(Path(сам.параметры["квитанция"]).read_text())
        сам.assertEqual("коммит-не-наблюдается", квитанция["состояние"])
        сам.assertEqual(1, квитанция["процесс"]["код"])
        сам.assertEqual("git commit", квитанция["профиль"][-1]["стадия"])
        крючок.unlink()
        сам.отказ_без_коммита(сам.создать)

    def test_поздняя_подмена_индекса_не_выдаёт_успех(сам):
        сам.готовить()
        крючок = сам.корень / ".git/hooks/pre-commit"
        крючок.write_text("#!/bin/sh\nprintf 'подмена\\n' > данные.txt\ngit add данные.txt\n")
        крючок.chmod(0o755)
        with сам.assertRaises(коммит.ОшибкаКоммита):
            сам.создать()
        сам.assertNotEqual(сам.начало, сам.гит("rev-parse", "HEAD").strip())
        квитанция = json.loads(Path(сам.параметры["квитанция"]).read_bytes())
        сам.assertEqual("расхождение-после-создания", квитанция["состояние"])
        сам.assertEqual(сам.гит("rev-parse", "HEAD").strip(), квитанция["наблюдённый_коммит"])

    def test_повтор_также_отвергает_перенаправляющую_среду(сам):
        сам.готовить()
        сам.создать()
        квитанция = Path(сам.параметры["квитанция"])

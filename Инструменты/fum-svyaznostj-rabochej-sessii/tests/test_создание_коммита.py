    def test_тайм_аут_завершает_дочерний_процесс_крючка(сам):
        крючок = сам.корень / ".git/hooks/pre-commit"
        крючок.write_text("#!/bin/sh\n(sleep 0.6; touch .git/поздняя-запись) &\nsleep 0.6\n")
        крючок.chmod(0o755)
        with mock.patch.object(коммит, "ПРЕДЕЛ_ГИТА", 0.1, create=True):
            with сам.assertRaises(коммит.ОшибкаКоммита):
                коммит.гит(сам.корень, "commit", "--allow-empty", "-m", "Проверка тайм-аута")
        time.sleep(0.7)
        сам.assertFalse((сам.корень / ".git/поздняя-запись").exists())

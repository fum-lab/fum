    def test_отказ_гита_сохраняет_квитанцию_и_не_повторяет_вызов(сам):
        сам.готовить()
        крючок = сам.корень / ".git/hooks/pre-commit"
        крючок.write_text("#!/bin/sh\nexit 1\n")
        крючок.chmod(0o755)
        сам.отказ_без_коммита(сам.создать)
        сам.assertTrue(Path(сам.параметры["квитанция"]).is_file())
        квитанция = json.loads(Path(сам.параметры["квитанция"]).read_text())
        сам.assertEqual("коммит-не-наблюдается", квитанция["состояние"])
        сам.assertEqual(1, квитанция["процесс"]["код"])
        сам.assertEqual("git commit", квитанция["профиль"][-1]["стадия"])
        крючок.unlink()
        сам.отказ_без_коммита(сам.создать)

    def test_поздняя_подмена_индекса_не_выдаёт_успех(сам):
        сам.готовить()
        крючок = сам.корень / ".git/hooks/pre-commit"
        крючок.write_text("#!/bin/sh\nprintf 'подмена\\n' > данные.txt\ngit add данные.txt\n")
        крючок.chmod(0o755)
        with сам.assertRaises(коммит.ОшибкаКоммита):
            сам.создать()
        сам.assertNotEqual(сам.начало, сам.гит("rev-parse", "HEAD").strip())
        квитанция = json.loads(Path(сам.параметры["квитанция"]).read_bytes())
        сам.assertEqual("расхождение-после-создания", квитанция["состояние"])
        сам.assertEqual(сам.гит("rev-parse", "HEAD").strip(), квитанция["наблюдённый_коммит"])


        with mock.patch.dict(os.environ, {"GIT_INDEX_FILE": str(сам.каталог / "чужой-индекс")}):
            with сам.assertRaises(коммит.ОшибкаКоммита):
                сам.создать()
        сам.assertEqual(прежнее, квитанция.read_bytes())


def исходный_снимок():
    исходник = subprocess.check_output(['git', '-C', str(КОРЕНЬ), 'show', БАЗА + ':' + ПУТЬ])
    дерево = ast.parse(исходник)
    функция = next(узел for узел in дерево.body if isinstance(узел, ast.FunctionDef)
                   and узел.name == 'снимок_обновления')
    область = dict(фасад.__dict__)
    exec(compile(ast.Module(body=[функция], type_ignores=[]), '<закреплённый Git-blob>', 'exec'), область)
    return область['снимок_обновления']


@contextlib.contextmanager
def наблюдать(корень):
    данные = {'перечисления': {}, 'чтения': 0, 'байты': 0, 'SHA': 0, 'в_пути': 0}
    прежний_путь = фасад.коммит.охват.точный_путь
    прежнее_чтение = Path.read_bytes
    прежнее_перечисление = Path.iterdir
    прежний_хэш = фасад.хэш

    def путь(основание, имя, кэш=None):
        данные['в_пути'] += 1
        try:
            return прежний_путь(основание, имя, кэш)
        finally:
            данные['в_пути'] -= 1

    def перечислить(каталог):
        if данные['в_пути'] and каталог.is_relative_to(корень):
            имя = каталог.relative_to(корень).as_posix()
            данные['перечисления'][имя] = данные['перечисления'].get(имя, 0) + 1
        yield from прежнее_перечисление(каталог)

    def прочитать(файл):
        результат = прежнее_чтение(файл)
        if файл.is_relative_to(корень) and '.git' not in файл.relative_to(корень).parts:
            данные['чтения'] += 1
            данные['байты'] += len(результат)
        return результат

    def хэш(байты):
        данные['SHA'] += 1
        return прежний_хэш(байты)

    with mock.patch.object(фасад.коммит.охват, 'точный_путь', путь), \
            mock.patch.object(Path, 'iterdir', перечислить), \
            mock.patch.object(Path, 'read_bytes', прочитать), \
            mock.patch.object(фасад, 'хэш', хэш):
        yield данные


class СтрогиеСнимки(unittest.TestCase):
    def setUp(сам):
        временный = tempfile.TemporaryDirectory()
        сам.addCleanup(временный.cleanup)
        сам.корень = Path(временный.name).resolve()
        сам.гит('init', '-q')
        сам.гит('config', 'user.name', 'Открытая фикстура')
        сам.гит('config', 'user.email', 'fixture@example.invalid')
        сам.сессии = []
        for номер in range(3):
            каталог = сам.корень / f'Журнал/2026-10-01_12-00-0{номер}_MSK_проверить-снимок-{номер}'
            каталог.mkdir(parents=True)
            (каталог / 'запрос.md').write_text(f'# Проверить снимок {номер}\n\nЗапрос.\n')
            (каталог / 'отчёт.md').write_text(f'# Отчёт {номер}\n\nРезультат.\n')
            сам.сессии.append(каталог)
        (сам.корень / 'Журнал/README.md').write_text('# Журнал\n\n## Сессии\n\n')
        (сам.корень / 'документ.md').write_text('# Проверяемый документ\n')
        сам.гит('add', '.')
        сам.гит('commit', '-qm', 'Закрепить открытый вход')
        сам.база = исходный_снимок()

    def гит(сам, *аргументы):
        return subprocess.check_output(['git', '-C', str(сам.корень), *аргументы],
                                       env={**os.environ, 'GIT_OPTIONAL_LOCKS': '0'})

    def граница(сам):
        файлы = {п.relative_to(сам.корень).as_posix():
                 (hashlib.sha256(п.read_bytes()).hexdigest(), stat.S_IMODE(п.stat().st_mode))
                 for п in сам.корень.rglob('*') if п.is_file() and '.git' not in п.parts}
        return файлы, сам.гит('rev-parse', 'HEAD'), (сам.корень / '.git/index').read_bytes()

    def test_каталог_перечисляется_один_раз_за_каждый_снимок(сам):
        for имя in ('журнал', 'recency'):
            for _ in range(2):
                with наблюдать(сам.корень) as счёт:
                    фасад.снимок_обновления(сам.корень, имя)
                сам.assertEqual(1, счёт['перечисления']['Журнал'])
                сам.assertTrue(all(число == 1 for число in счёт['перечисления'].values()), счёт)

    def test_точные_ключи_хэши_режимы_чтения_байты_и_индекс_совпадают(сам):
        до = сам.граница()
        for имя in ('журнал', 'recency'):
            with наблюдать(сам.корень) as счёт_базы:
                сам.база.__globals__['хэш'] = фасад.хэш
                старый = сам.база(сам.корень, имя)
            with наблюдать(сам.корень) as счёт_нового:
                новый = фасад.снимок_обновления(сам.корень, имя)
            сам.assertEqual(старый, новый)
            for поле in ('чтения', 'байты', 'SHA'):
                сам.assertEqual(счёт_базы[поле], счёт_нового[поле])
            существующие = sum(значение is not None for значение in новый.values())
            сам.assertEqual(существующие, счёт_нового['чтения'])
            сам.assertEqual(существующие, счёт_нового['SHA'])
        сам.assertEqual(до, сам.граница())

    def test_свежесть_байтов_режима_добавления_и_удаления_между_снимками(сам):
        for имя in ('журнал', 'recency'):
            исходный = фасад.снимок_обновления(сам.корень, имя)
            файл = сам.сессии[1] / 'запрос.md'
            файл.write_bytes(файл.read_bytes() + b'\n')
            файл.chmod(0o755 if stat.S_IMODE(файл.stat().st_mode) == 0o644 else 0o644)
            новый = фасад.снимок_обновления(сам.корень, имя)
            ключ = файл.relative_to(сам.корень).as_posix()
            сам.assertNotEqual(исходный[ключ]['sha256'], новый[ключ]['sha256'])
            сам.assertNotEqual(исходный[ключ]['режим'], новый[ключ]['режим'])
        папка = сам.корень / 'Журнал/2026-10-02_12-00-00_MSK_проверить-добавление'
        папка.mkdir(); файл = папка / 'запрос.md'; файл.write_text('# Добавленный запрос\n')
        for имя in ('журнал', 'recency'):
            сам.assertIn(файл.relative_to(сам.корень).as_posix(), фасад.снимок_обновления(сам.корень, имя))
        файл.unlink()
        for имя in ('журнал', 'recency'):
            сам.assertNotIn(файл.relative_to(сам.корень).as_posix(), фасад.снимок_обновления(сам.корень, имя))

    def изменить_после_первого_пути(сам, действие, способ=None):
        прежний = фасад.коммит.охват.точный_путь
        первый = (сам.сессии[0] / 'запрос.md').relative_to(сам.корень).as_posix()
        выполнено = False

        def путь(корень, имя, кэш=None):
            nonlocal выполнено
            результат = прежний(корень, имя, кэш)
            if имя == первый and not выполнено:
                выполнено = True
                действие()
            return результат

        with mock.patch.object(фасад.коммит.охват, 'точный_путь', путь):
            return (способ or фасад.снимок_обновления)(сам.корень, 'журнал')

    def test_изменённый_каталог_перечитывается_без_старого_положительного_ответа(сам):
        каталог = сам.сессии[0]
        с = каталог.stat()

        def изменить():
            (каталог / 'добавлено.txt').write_text('Допустимая новая запись.\n')
            os.utime(каталог, ns=(с.st_atime_ns, с.st_mtime_ns))

        with наблюдать(сам.корень) as счёт:
            итог = сам.изменить_после_первого_пути(изменить)
        сам.assertEqual(2, счёт['перечисления'][каталог.relative_to(сам.корень).as_posix()])
        сам.assertIn((каталог / 'отчёт.md').relative_to(сам.корень).as_posix(), итог)

    def test_регистр_и_ссылка_после_прогрева_сохраняют_прежний_отказ(сам):
        for вид in ('регистр', 'ссылка'):
            for способ in (сам.база, фасад.снимок_обновления):
                файл = сам.сессии[0] / 'отчёт.md'
                байты = файл.read_bytes()

                def изменить():
                    if вид == 'регистр':
                        файл.rename(файл.with_name('Отчёт.md'))
                    else:
                        файл.unlink(); файл.symlink_to(сам.сессии[1] / 'отчёт.md')

                try:
                    with сам.assertRaises(ValueError):
                        сам.изменить_после_первого_пути(изменить, способ)
                finally:
                    if вид == 'регистр':
                        файл.with_name('Отчёт.md').rename(файл)
                    else:
                        файл.unlink(); файл.write_bytes(байты)

    def test_замена_каталога_с_прежним_временем_требует_перечитывания(сам):
        каталог = сам.сессии[0]
        прежний = каталог.with_name(каталог.name + '-прежний')
        метка = каталог.stat()

        def заменить():
            каталог.rename(прежний)
            каталог.mkdir()
            for файл in прежний.iterdir():
                (каталог / файл.name).write_bytes(файл.read_bytes())
            os.utime(каталог, ns=(метка.st_atime_ns, метка.st_mtime_ns))
            сам.assertNotEqual(метка.st_ino, каталог.stat().st_ino)

        with наблюдать(сам.корень) as счёт:
            итог = сам.изменить_после_первого_пути(заменить)
        сам.assertEqual(2, счёт['перечисления'][каталог.relative_to(сам.корень).as_posix()])
        сам.assertIn((каталог / 'отчёт.md').relative_to(сам.корень).as_posix(), итог)

    def test_ошибки_метаданных_и_перечисления_не_используют_прогретый_кэш(сам):
        каталог = сам.сессии[0]
        for вид in ('stat', 'iterdir'):
            for номер, способ in enumerate((сам.база, фасад.снимок_обновления)):
                прежний = getattr(Path, вид)
                включено = False

                def ошибиться(путь, *аргументы, **ключи):
                    if включено and путь == каталог:
                        raise OSError('Открытая ошибка фикстуры')
                    return прежний(путь, *аргументы, **ключи)

                def изменить():
                    nonlocal включено
                    (каталог / f'потребовать-перечитывание-{вид}-{номер}.txt').write_text('Перечитать.\n')
                    включено = True

                with mock.patch.object(Path, вид, ошибиться):
                    with сам.assertRaises(ValueError):
                        сам.изменить_после_первого_пути(изменить, способ)
                сам.assertTrue(фасад.снимок_обновления(сам.корень, 'журнал'))

    def test_недопустимая_цель_сохраняет_отказ(сам):
        for цель in ('../чужое.md', '.git/config', '/чужое.md'):
            with mock.patch.object(фасад.каркас, '_canonical_requests', return_value={'ошибка': Path(цель)}):
                for способ in (сам.база, фасад.снимок_обновления):
                    with сам.assertRaises(ValueError):
                        способ(сам.корень, 'журнал')
        with сам.assertRaises(ValueError):
            фасад.коммит.охват.точный_путь(сам.корень, 'Журнал//README.md', {})

    def сведения(сам):
        return {'входы': фасад.снимок_обновления(сам.корень, 'журнал'), 'аргументы': []}

    def test_обновление_журнала_сохраняет_три_настоящих_снимка(сам):
        сведения = сам.сведения()
        with mock.patch.object(фасад, 'снимок_обновления', wraps=фасад.снимок_обновления) as снимки:
            фасад.обновить_журнал(сам.корень, {'Журнал/README.md'}, сведения)
        сам.assertEqual(3, снимки.call_count)

    def test_дрейф_после_построения_обнаруживается_до_переиндексации(сам):
        сведения = сам.сведения()
        прежний = фасад.каркас._index_text

        def построить(*аргументы, **ключи):
            итог = прежний(*аргументы, **ключи)
            (сам.сессии[1] / 'отчёт.md').write_text('# Дрейф после построения\n')
            return итог

        with mock.patch.object(фасад.каркас, '_index_text', построить), \
                mock.patch.object(фасад.каркас, 'reindex_journal', wraps=фасад.каркас.reindex_journal) as переиндексировать:
            with сам.assertRaisesRegex(ValueError, 'дрейф перед refresh'):
                фасад.обновить_журнал(сам.корень, {'Журнал/README.md'}, сведения)
            переиндексировать.assert_not_called()

    def test_третий_снимок_обнаруживает_изменение_чужого_входа(сам):
        сведения = сам.сведения()
        прежний = фасад.каркас.reindex_journal

        def переиндексировать(*аргументы, **ключи):
            итог = прежний(*аргументы, **ключи)
            (сам.сессии[1] / 'отчёт.md').write_text('# Чужой дрейф при refresh\n')
            return итог

        with mock.patch.object(фасад.каркас, 'reindex_journal', переиндексировать):
            with сам.assertRaisesRegex(ValueError, 'refresh изменил чужой вход'):
                фасад.обновить_журнал(сам.корень, {'Журнал/README.md'}, сведения)



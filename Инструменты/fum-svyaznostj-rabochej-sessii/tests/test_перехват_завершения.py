"""Проверяем границу нативного Stop через настоящий процесс и строгий backend."""
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import tempfile
import time
import unittest


СЦЕНАРИЙ = Path(__file__).resolve().parents[1] / "scripts/перехватить-завершение.py"
ЗАДАЧА = "01a07d3d-d376-7ad2-aafc-67e4c25a67eb"
ЧУЖАЯ = "00000000-0000-0000-0000-000000000002"
ФИКСТУРА = '''
import argparse
import json
import os
from pathlib import Path
import signal
import sys
import time
парсер = argparse.ArgumentParser()
парсер.add_argument("--корень-репозитория", required=True)
парсер.add_argument("--codex-thread-id", required=True)
парсер.add_argument("--перед-завершением", action="store_true", required=True)
парсер.add_argument("--план")
аргументы = парсер.parse_args()
корень = Path(аргументы.корень_репозитория)
(корень / "вызван").touch()
режим = (корень / "режим").read_text()
if режим == "ранний-сигнал":
    (корень / "pid").write_text(str(os.getpid()))
    os.kill(os.getppid(), signal.SIGTERM)
    time.sleep(20)
if режим == "тайм-аут":
    time.sleep(20)
if режим == "поток":
    while True:
        sys.stdout.write("x" * 8192)
        sys.stdout.flush()
if режим == "ошибка":
    sys.stderr.write("СЕКРЕТНЫЙ-МАРКЕР")
    raise SystemExit(2)
if режим == "сырой":
    print("{}")
    raise SystemExit(3)
ответ = json.loads((корень / "ответ.json").read_text())
print(json.dumps(ответ, ensure_ascii=False))
raise SystemExit(3 if ответ["решение"] == "продолжить" else 0)
'''


class ПерехватЗавершения(unittest.TestCase):
    def setUp(это):
        это.каталог = Path(это.enterContext(tempfile.TemporaryDirectory())).resolve()
        это.корень = это.каталог / "проект"
        это.корень.mkdir()
        это.состояние = это.каталог / "состояние"
        это.бэкенд = это.каталог / "guard.py"
        это.бэкенд.write_text(ФИКСТУРА, encoding="utf-8")
        это.ответ = {"схема": "fum.решение-продолжения.1", "задача": ЗАДАЧА,
                     "решение": "продолжить", "следующая_работа": "код",
                     "ожидающие_работы": [],
                     "вид_коммита": None}
        это.установить()
        (это.корень / "режим").write_text("нормально")
        (это.корень / "результат.py").write_text("начало")
        это.событие = {"session_id": ЗАДАЧА, "hook_event_name": "Stop", "turn_id": "ход-1",
                      "cwd": str(это.корень), "stop_hook_active": False,
                      "last_assistant_message": "СЕКРЕТНЫЙ-МАРКЕР", "transcript_path": "/приватное"}

    def установить(это):
        (это.корень / "ответ.json").write_text(json.dumps(это.ответ, ensure_ascii=False))

    def команда(это, *добавка):
        return [sys.executable, str(СЦЕНАРИЙ), "--корень-репозитория", str(это.корень),
                "--codex-thread-id", ЗАДАЧА, "--ожидаемый-cwd", str(это.корень),
                "--guard", str(это.бэкенд), "--каталог-состояния", str(это.состояние),
                "--файл-прогресса", "результат.py", "--предел-повторов", "2",
                "--тайм-аут-backend", "0.5", *добавка]

    def вызвать(это, вход=None, *добавка):
        if вход is None:
            вход = json.dumps(это.событие).encode()
        результат = subprocess.run(это.команда(*добавка), input=вход, capture_output=True, timeout=5,
                                  env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1"))
        это.assertEqual(результат.returncode, 0, результат.stderr.decode())
        это.assertNotIn("СЕКРЕТНЫЙ-МАРКЕР".encode(), результат.stdout)
        это.assertEqual(результат.stderr, b"")
        return json.loads(результат.stdout)

    def остановлен(это, ответ, код):
        это.assertIs(ответ["continue"], False)
        это.assertIn(код, ответ["stopReason"])
        это.assertNotIn("decision", ответ)

    def test_код3_становится_блокировкой_с_детерминированной_причиной(это):
        первый = это.вызвать()
        это.assertEqual(первый["decision"], "block")
        это.assertIn("код", первый["reason"])
        это.событие.update(turn_id="ход-2", stop_hook_active=True)
        это.assertEqual(это.вызвать(), первый)

    def test_чужая_задача_не_читает_проверку_и_не_создаёт_состояние(это):
        это.событие["session_id"] = ЧУЖАЯ
        это.бэкенд.unlink()
        это.assertEqual(это.вызвать(), {})
        это.assertFalse(это.состояние.exists())
        это.assertFalse((это.корень / "вызван").exists())

    def test_другое_событие_не_управляет_ходом(это):
        это.событие["hook_event_name"] = "SubagentStop"
        это.assertEqual(это.вызвать(), {})
        это.assertFalse(это.состояние.exists())

    def test_неопределённая_принадлежность_даёт_только_диагностику(это):
        for вход in (b"{}", b"null", b"{", b"\xff", b"x" * 65537,
                     b'{"session_id":"a","session_id":"b"}'):
            with это.subTest(вход=вход[:20]):
                ответ = это.вызвать(вход)
                это.assertEqual(set(ответ), {"systemMessage"})
        это.assertFalse(это.состояние.exists())

    def test_невалидное_целевое_событие_останавливает_с_диагностикой(это):
        for поле, значение in (("stop_hook_active", 1), ("turn_id", ""), ("cwd", "/чужой")):
            with это.subTest(поле=поле):
                исходное = это.событие[поле]
                это.событие[поле] = значение
                это.остановлен(это.вызвать(), "вход")
                это.событие[поле] = исходное

    def test_ошибка_тайм_аут_и_избыточный_вывод_не_разрешают_завершение(это):
        for режим in ("ошибка", "тайм-аут", "поток", "сырой"):
            with это.subTest(режим=режим):
                это.состояние = это.каталог / ("состояние-" + режим)
                (это.корень / "режим").write_text(режим)
                ответ = это.вызвать()
                это.assertEqual(ответ["decision"], "block")
                это.assertIn("guard", ответ["reason"])

    def test_нулевой_код_имеет_только_три_разрешённых_решения(это):
        for решение in ("завершить", "ожидать-ответа", "остановлено-пользователем"):
            это.ответ.update(решение=решение, следующая_работа=None)
            это.ответ["ожидающие_работы"] = ["вопрос"] if решение == "ожидать-ответа" else []
            это.установить()
            ответ = это.вызвать()
            if решение == "остановлено-пользователем":
                это.остановлен(ответ, "пользователем")
            else:
                это.assertEqual(ответ, {})

    def test_чужой_ответ_проверки_и_неизвестная_схема_не_принимаются(это):
        for поле, значение in (("задача", ЧУЖАЯ), ("схема", "неизвестная"),
                               ("решение", "успешно")):
            это.состояние = это.каталог / ("состояние-" + поле)
            исходное = это.ответ[поле]
            это.ответ[поле] = значение
            это.установить()
            ответ = это.вызвать()
            это.assertEqual(ответ["decision"], "block")
            это.assertIn("guard", ответ["reason"])
            это.ответ[поле] = исходное

    def test_предел_повторов_не_сбрасывается_новым_ходом_или_флагом(это):
        это.assertEqual(это.вызвать()["decision"], "block")
        это.событие.update(turn_id="ход-2", stop_hook_active=True)
        это.assertEqual(это.вызвать()["decision"], "block")
        это.событие.update(turn_id="ход-3", stop_hook_active=False)
        это.остановлен(это.вызвать(), "повторов")
        это.ответ.update(решение="остановлено-пользователем", следующая_работа=None)
        это.установить()
        это.остановлен(это.вызвать(), "пользователем")

    def test_изменённый_результат_позволяет_продолжить_а_возврат_не_новый_прогресс(это):
        это.вызвать()
        это.вызвать()
        (это.корень / "результат.py").write_text("новый результат")
        это.assertEqual(это.вызвать()["decision"], "block")
        (это.корень / "результат.py").write_text("начало")
        это.остановлен(это.вызвать(), "повторов")

    def test_общий_предел_не_обходится_изменениями(это):
        for номер in range(3):
            (это.корень / "результат.py").write_text(str(номер))
            ответ = это.вызвать(None, "--предел-продолжений", "2")
        это.остановлен(ответ, "продолжений")

    def test_состояние_хранит_только_счётчики_и_хэши(это):
        это.вызвать()
        путь = это.состояние / (ЗАДАЧА + ".json")
        состояние = json.loads(путь.read_text())
        это.assertEqual(set(состояние), {"схема", "задача", "продолжений", "отпечатки"})
        это.assertNotIn("СЕКРЕТНЫЙ-МАРКЕР", путь.read_text())
        это.assertEqual(путь.stat().st_mode & 0o777, 0o600)
        это.assertEqual(это.состояние.stat().st_mode & 0o777, 0o700)

    def test_повреждённое_состояние_не_пересоздаётся(это):
        это.вызвать()
        путь = это.состояние / (ЗАДАЧА + ".json")
        путь.write_text("{")
        это.остановлен(это.вызвать(), "состояние")
        это.assertEqual(путь.read_text(), "{")

    def test_состояние_в_рабочем_дереве_и_символические_ссылки_отклоняются(это):
        это.состояние = это.корень / "состояние"
        это.остановлен(это.вызвать(), "состояние")
        это.assertFalse(это.состояние.exists())
        это.состояние = это.каталог / "ссылка"
        это.состояние.symlink_to(это.корень, target_is_directory=True)
        это.остановлен(это.вызвать(), "состояние")

    def test_параллельный_вход_не_теряет_счётчики(это):
        процессы = [subprocess.Popen(это.команда(), stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                    stderr=subprocess.PIPE) for _ in range(3)]
        for процесс in процессы:
            процесс.stdin.write(json.dumps(это.событие).encode())
            процесс.stdin.close()
            процесс.stdin = None
        ответы = [json.loads(процесс.communicate(timeout=5)[0]) for процесс in процессы]
        это.assertEqual(sum(ответ.get("decision") == "block" for ответ in ответы), 2)
        это.assertEqual(sum(ответ.get("continue") is False for ответ in ответы), 1)

    def test_прерывание_не_возобновляет_задачу(это):
        (это.корень / "режим").write_text("тайм-аут")
        процесс = subprocess.Popen(это.команда("--тайм-аут-backend", "3"), stdin=subprocess.PIPE,
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        процесс.stdin.write(json.dumps(это.событие).encode())
        процесс.stdin.close()
        процесс.stdin = None
        предел = time.monotonic() + 3
        while not (это.корень / "вызван").exists() and time.monotonic() < предел:
            time.sleep(0.01)
        процесс.send_signal(signal.SIGTERM)
        вывод, ошибки = процесс.communicate(timeout=3)
        это.assertEqual(процесс.returncode, 0, ошибки)
        это.остановлен(json.loads(вывод), "прерван")

    def test_незакрытый_ввод_ограничен_временем(это):
        процесс = subprocess.Popen(это.команда("--тайм-аут-ввода", "0.1"),
                                   stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        процесс.wait(timeout=3)
        это.assertEqual(set(json.loads(процесс.stdout.read())), {"systemMessage"})
        процесс.stdin.close()
        процесс.stdout.close()
        процесс.stderr.close()

    def test_первая_ошибка_проверки_повторяется_а_цикл_ограничен(это):
        (это.корень / "режим").write_text("ошибка")
        for _ in range(2):
            это.assertEqual(это.вызвать()["decision"], "block")
        это.остановлен(это.вызвать(), "повторов")

    def test_именованный_канал_прогресса_не_блокирует_адаптер(это):
        путь = это.корень / "результат.py"
        путь.unlink()
        os.mkfifo(путь)
        это.остановлен(это.вызвать(), "прогресса")

    def test_граница_ввода_и_глубокие_структуры(это):
        это.событие["session_id"] = ЧУЖАЯ
        вход = json.dumps(это.событие).encode()
        это.assertEqual(это.вызвать(вход + b" " * (65536 - len(вход))), {})
        это.assertEqual(set(это.вызвать(вход + b" " * (65537 - len(вход)))), {"systemMessage"})
        это.assertEqual(set(это.вызвать(b"[" * 2000 + b"]" * 2000)), {"systemMessage"})

    def test_изменённый_ответ_или_тип_ошибки_не_являются_прогрессом(это):
        это.вызвать()
        это.ответ["следующая_работа"] = "другая-работа"
        это.установить()
        это.вызвать()
        (это.корень / "режим").write_text("ошибка")
        это.остановлен(это.вызвать(), "повторов")

    def test_раннее_прерывание_убирает_процесс_проверки(это):
        (это.корень / "режим").write_text("ранний-сигнал")
        это.остановлен(это.вызвать(), "прерван")
        номер = int((это.корень / "pid").read_text())
        with это.assertRaises(ProcessLookupError):
            os.kill(номер, 0)

    def test_пользовательская_остановка_выше_повреждённого_состояния(это):
        это.вызвать()
        (это.состояние / (ЗАДАЧА + ".json")).write_text("{")
        это.ответ.update(решение="остановлено-пользователем", следующая_работа=None)
        это.установить()
        это.остановлен(это.вызвать(), "пользователем")

    def второй_контракт(это):
        это.ответ.update(схема="fum.решение-продолжения.2", незавершённые_обязательства=["исходный-результат"],
                        HEAD="a" * 40, доказательства={})

    def test_второй_контракт_с_нулевой_следующей_работой_восстанавливает_план(это):
        это.второй_контракт()
        это.ответ["следующая_работа"] = None
        это.установить()
        ответ = это.вызвать()
        это.assertEqual(ответ["decision"], "block")
        это.assertIn("восстанови", ответ["reason"])
        это.assertNotIn("guard-ответ", ответ["reason"])

    def test_второй_контракт_разрешает_только_согласованные_нулевые_решения(это):
        это.второй_контракт()
        это.ответ.update(решение="завершить", следующая_работа=None, незавершённые_обязательства=[])
        это.установить()
        это.assertEqual(это.вызвать(), {})
        это.ответ.update(решение="ожидать-ответа", ожидающие_работы=["вопрос"], незавершённые_обязательства=["код"])
        это.установить()
        это.assertEqual(это.вызвать(), {})
        это.ответ.update(решение="остановлено-пользователем", ожидающие_работы=[], незавершённые_обязательства=[])
        del это.ответ["HEAD"]
        del это.ответ["доказательства"]
        это.установить()
        это.остановлен(это.вызвать(), "пользователем")

    def test_пустое_продолжение_второго_контракта_ограничено_как_ошибка(это):
        это.второй_контракт()
        это.ответ.update(следующая_работа=None, незавершённые_обязательства=[])
        это.установить()
        for _ in range(2):
            ответ = это.вызвать()
            это.assertEqual(ответ["decision"], "block")
            это.assertIn("guard-ответ", ответ["reason"])
            это.assertIn("план и реестр", ответ["reason"])
        это.остановлен(это.вызвать(), "прогресса")

    def test_противоречивый_второй_контракт_не_разрешает_завершение(это):
        это.второй_контракт()
        варианты = [dict(решение="завершить", следующая_работа=None),
                    dict(решение="ожидать-ответа", следующая_работа=None),
                    dict(следующая_работа=None, незавершённые_обязательства=[]),
                    dict(HEAD="не-OID"), dict(доказательства={"код": ["не-OID"]}),
                    dict(лишнее=True)]
        исходный = dict(это.ответ)
        for номер, изменения in enumerate(варианты):
            with это.subTest(изменения=изменения):
                это.состояние = это.каталог / ("отказ-" + str(номер))
                это.ответ = dict(исходный, **изменения)
                это.установить()
                ответ = это.вызвать()
                это.assertEqual(ответ["decision"], "block")
                это.assertIn("guard-ответ", ответ["reason"])


if __name__ == "__main__":
    unittest.main()

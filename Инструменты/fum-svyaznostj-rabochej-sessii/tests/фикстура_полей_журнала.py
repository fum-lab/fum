"""Открытая пара документов для проверки раннего допуска полей."""

from pathlib import Path


def создать_пару(корень: Path) -> Path:
    папка = корень / "Журнал/2026-09-15_00-00-00_MSK_проверить-поля"
    папка.mkdir(parents=True)
    реестр = корень / "Инструменты/реестр-системных-приложений-и-инструментов.md"
    реестр.parent.mkdir()
    реестр.write_text("# Открытый реестр\n", encoding="utf-8")
    запрос = папка / "запрос.md"
    запрос.write_text(
        "# Исходный запрос 2026-09-15 00:00:00 MSK - Проверить поля\n\n"
        "## Текст запроса\n\nПроверить поля.\n\n"
        "## Идентификатор сеанса Codex\n\n"
        "Codex-Thread-ID: 00000000-0000-0000-0000-000000000000\n\n"
        "## Использованные инструменты\n\n"
        "- Python 3.\n"
        "- fum-moskovskoye-vremya-rabochej-sessii; "
        "[реестр](../../Инструменты/реестр-системных-приложений-и-инструментов.md).\n\n"
        "## Повлиял на файлы\n\n- [Запрос](запрос.md).\n- [Отчёт](отчёт.md).\n",
        encoding="utf-8",
    )
    (папка / "отчёт.md").write_text(
        "# Отчёт 2026-09-15 00:00:00 MSK - Проверить поля\n\n"
        "Синтетический результат.\n\n## Профиль времени выполнения\n\n"
        "| Стадия | Длительность | Границы и способ измерения |\n"
        "| --- | --- | --- |\n| Подготовка | Не измерено | До проверки |\n"
        "| Проверка | 1 с | Синтетическое значение |\n\n"
        "Граница профиля: только синтетический пример.\n\n"
        "### Прямые запуски проверок\n\n"
        "| Вызов | Длительность | Результат |\n| --- | --- | --- |\n"
        "| Синтетический пример | 1 с | успешно |\n\n"
        "Общее время прямых запусков проверок: 1 с.\n\n"
        "## Источники\n\n[Исходный запрос](запрос.md).\n",
        encoding="utf-8",
    )
    return запрос

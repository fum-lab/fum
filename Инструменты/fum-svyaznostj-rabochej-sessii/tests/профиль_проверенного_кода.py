"""Два воспроизводимых открытых набора; три раздельных интервала."""
import argparse
import hashlib
import json
from pathlib import Path
import statistics
import sys
import time
from test_проверенного_кода import Фикстура


def измерить(число):
    набор = Фикстура(число)
    try:
        начало = time.perf_counter_ns()
        снимок = набор.снимок()
        удержание = time.perf_counter_ns() - начало
        начало = time.perf_counter_ns()
        сеанс = снимок.исполнение()
        компиляция = time.perf_counter_ns() - начало
        начало = time.perf_counter_ns()
        with сеанс:
            результат = [сеанс.загрузить(f"контур.набор{н}").значение for н in range(число)]
            программа = сеанс.загрузить("контур.программа")
            assert программа.значение == "Q:кириллица" and программа.позже() == 73
        загрузка = time.perf_counter_ns() - начало
        assert результат == list(range(число))
        return {"коммит_Q": снимок.коммит, "число_модулей": len(снимок.байты),
            "удержанные_исходные_байты": снимок.объём_байтов, "получение_снимка_нс": удержание,
            "чтение_сверка_нс": снимок.чтение_сверка_нс, "компиляция_входа_нс": снимок.компиляция_входа_нс,
            "компиляция_набора_нс": компиляция, "загрузка_и_вызов_нс": загрузка}
    finally:
        набор.закрыть()


def главное():
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument("--набор", choices=("малый", "пакет"), required=True)
    разборщик.add_argument("--выход", type=Path, required=True)
    параметры = разборщик.parse_args()
    число = 2 if параметры.набор == "малый" else 16
    прогрев = измерить(число)
    измерения = [измерить(число) for _ in range(3)]
    for запись in измерения:
        assert (запись["коммит_Q"], запись["удержанные_исходные_байты"]) == (
            прогрев["коммит_Q"], прогрев["удержанные_исходные_байты"])
    пути = [Path(__file__), Path(__file__).with_name("test_проверенного_кода.py")]
    пути += sorted((Path(__file__).resolve().parents[1] / "scripts" / "проверенный_код").glob("*.py"))
    результат = {"схема": "fum.профиль-проверенного-кода.1", "набор": параметры.набор,
        "python": sys.version.split()[0], "источники_sha256": {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in пути},
        "прогрев": прогрев, "измерения": измерения,
        "медианы_нс": {к: int(statistics.median(з[к] for з in измерения)) for к in прогрев if к.endswith("_нс")},
        "граница": "Установка Git-фикстуры исключена. Получение снимка содержит чтение/сверку и компиляцию входа; эти вложенные интервалы не суммируются с ним. Компиляция набора и загрузка идут последовательно. Объём — сумма удержанных исходных байтов, не RSS и не память кодовых объектов."}
    with параметры.выход.open("x", encoding="utf-8") as выход:
        json.dump(результат, выход, ensure_ascii=False, sort_keys=True, indent=2)
        выход.write("\n")
    print(json.dumps({"набор": параметры.набор, "медианы_нс": результат["медианы_нс"],
        "удержанные_исходные_байты": прогрев["удержанные_исходные_байты"]}, ensure_ascii=False))


if __name__ == "__main__":
    главное()

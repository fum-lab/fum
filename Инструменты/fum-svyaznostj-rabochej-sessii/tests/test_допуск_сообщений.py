class ДопускСообщений(unittest.TestCase):
    def setUp(это):
        это.фикстура = фикстуры.ПроверкаОбработки()
        это.фикстура.setUp()
        это.addCleanup(это.фикстура.doCleanups)
        это.корень = это.фикстура.корень.resolve()
        это.источник = это.фикстура.источник.resolve()
        это.фикстура.запрос = "Журнал/2026-09-11_00-00-00_MSK_проверить-допуск/запрос.md"
        (это.корень / это.фикстура.запрос).parent.mkdir(parents=True)
        это.план = {"схема": "fum.продолжение-задачи.1", "задача": фикстуры.ЗАДАЧА,
                    "режим": "разовая", "остановка": None,
                    "работы": [{"идентификатор": "результат", "действие": "Сохранить результат",
                                "состояние": "завершена", "свидетельство": "Проверено.",
                                "основание": {"запрос": это.фикстура.запрос, "цитата": "Сделай."}}]}
        путь = это.корень / это.фикстура.запрос
        путь.write_text("# Источник\n\n## Текст запроса\n\n````text\nСделай.\n````\n\n````text\nПозднее уточнение.\n````\n\n````text\nОстановись.\n````\n\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: " + фикстуры.ЗАДАЧА + "\n")
        это.сохранить_план()
        это.фикстура.коммит()

    def сохранить_план(это):
        (это.корень / "план.json").write_text(json.dumps(это.план, ensure_ascii=False))

    def обработать_первое(это):
        снимок = это.фикстура.остаток()
        это.фикстура.сохранить(это.фикстура.предложение(снимок), снимок)
        это.фикстура.коммит()

    def команда(это, *аргументы):
        return [sys.executable, "-I", "-S", "-B", str(СЦЕНАРИЙ), "--корень-репозитория", str(это.корень),
                "--codex-thread-id", фикстуры.ЗАДАЧА, "--план", "план.json", "--перед-завершением", *аргументы]

    def вызвать(это, *аргументы):
        return subprocess.run(это.команда("--исходник", str(это.источник), *аргументы), capture_output=True, text=True)

    def test_исходник_обязателен_без_обхода(это):
        итог = subprocess.run(это.команда(), capture_output=True, text=True)
        это.assertEqual(итог.returncode, 2)
        это.assertFalse(итог.stdout)

    def test_необработанное_сообщение_закрывает_завершение(это):
        итог = это.вызвать()
        это.assertEqual(итог.returncode, 3, итог.stderr)
        ответ = json.loads(итог.stdout)
        это.assertEqual(ответ["схема"], "fum.решение-продолжения.3")
        это.assertEqual(ответ["обязательства"]["решение"], "завершить")
        это.assertEqual(ответ["сообщения"]["остаток"], 1)
        это.assertEqual(АДАПТЕР.проверить_решение(ответ, 3, фикстуры.ЗАДАЧА), ответ)
        for приватное in ("Сделай.", str(это.источник), '"экземпляры"', '"источник"', '"профиль"'):
            это.assertNotIn(приватное, итог.stdout)

    def test_пустой_остаток_сохраняет_незавершённую_работу(это):
        это.обработать_первое()
        это.план["работы"][0].update(состояние="доступна", свидетельство=None)
        это.сохранить_план()
        итог = это.вызвать()
        это.assertEqual(итог.returncode, 3, итог.stderr)
        ответ = json.loads(итог.stdout)
        это.assertTrue(ответ["сообщения"]["разбор_сообщений_завершён"])
        это.assertEqual(ответ["обязательства"]["следующая_работа"], "результат")

    def test_полный_разбор_и_готовые_работы_разрешают_завершение(это):
        это.обработать_первое()
        итог = это.вызвать()
        это.assertEqual(итог.returncode, 0, итог.stderr)
        ответ = json.loads(итог.stdout)
        это.assertEqual(ответ["решение"], "завершить")
        это.assertEqual(АДАПТЕР.проверить_решение(ответ, 0, фикстуры.ЗАДАЧА), ответ)

    def test_позднее_сообщение_возвращает_обработанное_на_сверку(это):
        это.обработать_первое()
        это.фикстура.добавить("Позднее уточнение.\n", 2)
        итог = это.вызвать()
        это.assertEqual(итог.returncode, 3, итог.stderr)
        это.assertEqual(json.loads(итог.stdout)["сообщения"]["остаток"], 2)

    def test_неизвестный_хвост_не_даёт_допуск(это):
        это.обработать_первое()
        with это.источник.open("ab") as поток:
            поток.write(b'{"type":')
        итог = это.вызвать()
        это.assertEqual(итог.returncode, 3, итог.stderr)
        сводка = json.loads(итог.stdout)["сообщения"]
        это.assertGreater(сводка["непроверенный_хвост"], 0)
        это.assertFalse(сводка["полнота_источника"])

    def test_источник_повреждён_или_принадлежит_другой_задаче(это):
        исходное = это.источник.read_bytes()
        for байты in (b"not json\n", исходное.replace(фикстуры.ЗАДАЧА.encode(), b"00000000-0000-0000-0000-000000000999")):
            with это.subTest(байты=байты[:20]):
                это.источник.write_bytes(байты)
                итог = это.вызвать()
                это.assertEqual(итог.returncode, 2, итог.stdout)
                это.assertFalse(итог.stdout)

    def test_повреждённая_история_и_утраченное_свидетельство(это):
        это.обработать_первое()
        история = это.фикстура.путь_истории.read_bytes()
        это.фикстура.путь_истории.write_bytes(b"{}\n")
        это.assertEqual(это.вызвать().returncode, 2)
        это.фикстура.путь_истории.write_bytes(история)
        (это.корень / это.фикстура.отчёт).write_text("Свидетельство утрачено.\n")
        итог = это.вызвать()
        это.assertEqual(итог.returncode, 3, итог.stderr)
        это.assertEqual(json.loads(итог.stdout)["сообщения"]["остаток"], 1)

    def test_остановка_имеет_приоритет_при_недоступном_JSONL(это):
        это.план["остановка"] = {"запрос": это.фикстура.запрос, "цитата": "Остановись."}
        это.сохранить_план()
        это.источник.unlink()
        итог = это.вызвать()
        это.assertEqual(итог.returncode, 0, итог.stderr)
        ответ = json.loads(итог.stdout)
        это.assertEqual(ответ["решение"], "остановлено-пользователем")
        это.assertIsNone(ответ["сообщения"])
        это.assertEqual(АДАПТЕР.проверить_решение(ответ, 0, фикстуры.ЗАДАЧА), ответ)

    def test_чтение_не_создаёт_кэш_замок_или_байткод(это):
        def снимок():
            return {str(п.relative_to(это.фикстура.каталог)): hashlib.sha256(п.read_bytes()).hexdigest()
                    for п in это.фикстура.каталог.rglob("*") if п.is_file()}
        до = снимок()
        итог = это.вызвать("--кэш", str(это.фикстура.каталог / "новый-кэш.json"))
        это.assertEqual(итог.returncode, 3, итог.stderr)
        это.assertEqual(до, снимок())
        это.assertFalse((это.фикстура.каталог / "новый").exists())

    def test_строгий_v3_не_принимает_противоречивый_допуск(это):
        итог = это.вызвать()
        это.assertEqual(итог.returncode, 3, итог.stderr)
        исходное = json.loads(итог.stdout)
        варианты = []
        ответ = copy.deepcopy(исходное); ответ.pop("сообщения"); варианты.append(ответ)
        ответ = copy.deepcopy(исходное); ответ["сообщения"] = None; варианты.append(ответ)
        ответ = copy.deepcopy(исходное); ответ["сообщения"]["остаток"] = False; варианты.append(ответ)
        ответ = copy.deepcopy(исходное); ответ["сообщения"]["разбор_сообщений_завершён"] = True; варианты.append(ответ)
        ответ = copy.deepcopy(исходное); ответ["сообщения"]["текст"] = "Приватное"; варианты.append(ответ)
        ответ = copy.deepcopy(исходное); ответ["обязательства"]["задача"] = "чужая"; варианты.append(ответ)
        ответ = copy.deepcopy(исходное); ответ["решение"] = "завершить"; варианты.append(ответ)
        for ответ in варианты:
            with это.subTest(ответ=ответ), это.assertRaises(АДАПТЕР.Отказ):
                АДАПТЕР.проверить_решение(ответ, 3 if ответ["решение"] == "продолжить" else 0, фикстуры.ЗАДАЧА)


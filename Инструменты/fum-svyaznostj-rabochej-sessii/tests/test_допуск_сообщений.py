class ОбщаяГраницаV2(unittest.TestCase):
    def test_поздняя_мутация_не_сохраняет_готовое_решение(это):
        for вид in ("код", "права", "инвентарь", "HEAD"):
            with это.subTest(вид=вид):
                пример = фикстуры_обязательств.ОбязательстваЗадачи()
                try:
                    пример.подготовить()
                    пример.принять()
                    пример.коммит()
                    описание = importlib.util.spec_from_file_location("общая_граница", СЦЕНАРИЙ)
                    модуль = importlib.util.module_from_spec(описание)
                    описание.loader.exec_module(модуль)
                    исходная = фикстуры.МОДУЛЬ.получить_остаток
                    def прочитать_и_изменить(*аргументы, **именованные):
                        ответ = исходная(*аргументы, **именованные)
                        код = пример.корень / "код.py"
                        if вид == "код":
                            код.write_text("print('Новое поведение')\n")
                        elif вид == "права":
                            код.chmod(код.stat().st_mode ^ 0o100)
                        elif вид == "инвентарь":
                            каталог = пример.корень / Path(пример.запрос).parent / "материалы/запуски-проверок"
                            (каталог / "новый.json").write_text("{}\n")
                        else:
                            пример.записать("поздний.txt", "Новый снимок\n")
                            пример.коммит()
                        return ответ
                    команда = [str(СЦЕНАРИЙ), "--корень-репозитория", str(пример.корень),
                               "--codex-thread-id", фикстуры_обязательств.ИДЕНТИФИКАТОР,
                               "--исходник", str(пример.исходник), "--перед-завершением"]
                    with mock.patch.dict(sys.modules, {"обработка_сообщений": фикстуры.МОДУЛЬ}), \
                            mock.patch.object(фикстуры.МОДУЛЬ, "получить_остаток", side_effect=прочитать_и_изменить), \
                            mock.patch.object(sys, "argv", команда), \
                            mock.patch.object(sys, "stdout", io.StringIO()) as вывод, \
                            mock.patch.object(sys, "stderr", io.StringIO()):
                        это.assertEqual(модуль.выполнить(), 2)
                        это.assertEqual(вывод.getvalue(), "")
                finally:
                    пример.doCleanups()


if __name__ == "__main__":
    unittest.main()

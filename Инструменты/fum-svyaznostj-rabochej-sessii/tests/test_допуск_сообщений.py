    def test_план_меняется_между_проверками_обязательств_и_сообщений(это):
        это.обработать_первое()
        описание = importlib.util.spec_from_file_location("составной_допуск", СЦЕНАРИЙ)
        модуль = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(модуль)
        исходная = фикстуры.МОДУЛЬ.получить_остаток
        def прочитать_и_изменить(*аргументы, **именованные):
            ответ = исходная(*аргументы, **именованные)
            это.план["работы"][0].update(состояние="доступна", свидетельство=None)
            это.сохранить_план()
            return ответ
        with mock.patch.dict(sys.modules, {"обработка_сообщений": фикстуры.МОДУЛЬ}), \
                mock.patch.object(фикстуры.МОДУЛЬ, "получить_остаток", side_effect=прочитать_и_изменить), \
                mock.patch.object(sys, "argv", это.команда("--исходник", str(это.источник))[4:]), \
                mock.patch.object(sys, "stdout", io.StringIO()), mock.patch.object(sys, "stderr", io.StringIO()):
            это.assertEqual(модуль.выполнить(), 2)


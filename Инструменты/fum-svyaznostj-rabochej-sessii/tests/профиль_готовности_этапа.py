"""Монотонный профиль решения при 0 и 1000 поздних сообщений; без Git и сети."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import statistics
import time

from test_готовность_этапа import ГотовностьЭтапа, готовность
from test_фиксация_командной_строки import ФиксацияКоманднойСтроки


def хэш(значение):
    return hashlib.sha256(json.dumps(значение, ensure_ascii=False, sort_keys=True).encode()).hexdigest()


def измерить(выход):
    пример = ГотовностьЭтапа(); пример.setUp()
    корень = Path(__file__).resolve().parents[1]
    пути = [Path(готовность.__file__), Path(__file__), Path(__file__).with_name("test_готовность_этапа.py"),
            Path(__file__).with_name("test_фиксация_командной_строки.py"),
            *[корень / "scripts" / имя for имя in ("контролировать-фиксацию.py", "история_модели.py", "сообщения_задачи.py")]]
    исходники = {str(п.relative_to(корень)): hashlib.sha256(п.read_bytes()).hexdigest() for п in пути}
    наблюдения = []
    for имя, поздние, время in (("до порога", [], пример.начало + 1_000_000_000),
                               ("порог ожидания", [], пример.начало + 600_000_000_000),
                               ("тысяча поздних сообщений", [f"{номер:064x}" for номер in range(1000)], пример.начало + 601_000_000_000)):
        вход = [пример.запись, пример.снимок, поздние, время]
        ожидаемое = готовность.оценить(*вход)
        assert ожидаемое["действие"] == "зафиксировать-этап" and ожидаемое["следующий_этап"] == поздние
        assert ожидаемое["задержка"] == (имя != "до порога")
        серии = []
        for _ in range(5):
            начало = time.perf_counter_ns()
            for _ in range(1000):
                результат = готовность.оценить(*вход)
            серии.append((time.perf_counter_ns() - начало) / 1000)
            assert результат == ожидаемое
        наблюдения.append({"сценарий": имя, "вход_sha256": хэш(вход), "выход_sha256": хэш(ожидаемое),
                            "серии_наносекунды_на_вызов": серии, "медиана_наносекунды": statistics.median(серии)})
    команда = ФиксацияКоманднойСтроки()
    try:
        команда.setUp()
        assert команда.вызвать("объявить", "--предел-секунд", "600").returncode == 0
        серии = []; возрасты = []
        for _ in range(5):
            начало = time.perf_counter_ns()
            процесс = команда.вызвать("сверить")
            серии.append(time.perf_counter_ns() - начало)
            assert процесс.returncode == 0
            результат = json.loads(процесс.stdout)
            assert результат["действие"] == "зафиксировать-этап"
            возрасты.append(результат["возраст_наносекунды"])
        assert возрасты == sorted(возрасты)
        наблюдения.append({"сценарий": "полный процесс сверки с сохранением возраста", "серии_наносекунды_на_вызов": серии,
                            "медиана_наносекунды": statistics.median(серии), "возрасты_наносекунды": возрасты})
    finally:
        команда.doCleanups()
    assert исходники == {str(п.relative_to(корень)): hashlib.sha256(п.read_bytes()).hexdigest() for п in пути}
    итог = {"схема": "fum.профиль-готовности-этапа.1", "исходники": исходники,
            "версия_интерпретатора": platform.python_version(), "архитектура": platform.machine(),
            "граница": "Чистые решения: пять серий по тысяче вызовов; подготовка исключена. CLI: пять полных процессов с чтением, замком и fsync, объявление готовности исключено. Git и сеть не вызываются; кэш ОС не очищается.",
            "наблюдения": наблюдения}
    выход.write_text(json.dumps(итог, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    измерить(разбор.parse_args().выход)

def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def замер(действие):
    начало=time.perf_counter_ns(); результат=действие()
    return результат,time.perf_counter_ns()-начало


def образец(вариант):
    пример=примеры.ПодготовкаПоручения(); начало=time.perf_counter_ns()
    try:
        пример.setUp()
        if вариант=='координация': пример.сохранить_координацию()
        выбор=пример.подготовить_акт(); подготовка=time.perf_counter_ns()-начало
        исходный=пример.ф.снимок()
        основание,время_основания=замер(lambda:генератор.проверить_координацию(пример.ф.корень,пример.решение,пример.вход))
        план,время_плана=замер(lambda:генератор.построить_план(пример.вход))
        пакет,время_приглашения=замер(lambda:генератор.составить_приглашение(пример.ф.корень,
            пример.вход['решение'],выбор,пример.вход if основание is not None else None))
        assert пример.ф.снимок()==исходный
        assert пакет['текст']==план['приглашение']
        assert хэш(пакет['текст'].encode())==план['нативная_привязка']['хэш_нативного_поручения']
        if основание is None:
            прежний=(пример.решение['поручение']+'\n\nПостановка: '+выбор['путь']+'\nКоммит: '+выбор['коммит']
                +'\nСырой SHA-256: '+выбор['sha256']+'\n')
            assert пакет['текст']==прежний
        else:
            assert основание==план['координация']
            assert all(э['текст'] in пакет['текст'] for э in основание['оригиналы'])
            assert 'Подтверждение получения требуется' in пакет['текст']
            assert str(пример.ф.приватный) not in пакет['текст']
        файл=Path(пример.вход['каталог_выходов'])/'профиль-план.json'
        сырые=генератор.байты(план);файл.write_bytes(сырые);файл.chmod(0o400)
        результат,время_установки=замер(lambda:генератор.применить(пример.вход,файл,хэш(сырые)))
        for установка in план['установка']:
            assert хэш(Path(установка['путь']).read_bytes())==установка['sha256']
        assert not план['внешние_действия']
        return {'вариант':вариант,'подготовка_вне_таймеров_нс':подготовка,
            'основание_нс':время_основания if основание is not None else None,
            'план_нс':время_плана,'приглашение_нс':время_приглашения,'применение_нс':время_установки,
            'хэш_плана':хэш(сырые),'хэш_приглашения':хэш(пакет['текст'].encode()),
            'приглашение_байтов':len(пакет['текст'].encode()),'установок':len(план['установка']),
            'исходных_байтов':Path(пример.вход['источники'][0]['путь']).stat().st_size,
            'исход_и_оригиналы_сверены':True}
    finally: пример.doCleanups()


def образец_дописывания(модуль):
    import test_поздней_привязки_журнала as позднее
    пример=позднее.ИсторическоеОснование();пример.setUp()
    try:
        событие=позднее.служебная_оболочка({'type':'response_item','payload':{
            'type':'function_call_output','call_id':'call_1','output':'Наблюдение.'*100}})
        пример.строки.extend([позднее.примеры.байты(событие)]*256);пример.обновить()
        исходное=пример.источник.read_bytes();контекст=пример.смысл['контекст']
        читатель=позднее.примеры.читатель;читать=читатель._прочитать_поток;разборы=[]
        def с_дописыванием(*аргументы,**параметры):
            начало=time.perf_counter_ns();результат=читать(*аргументы,**параметры)
            разборы.append({'длительность_нс':time.perf_counter_ns()-начало,'профиль':результат[1]})
            with пример.источник.open('ab') as поток: поток.write(позднее.примеры.байты(событие))
            return результат
        наблюдение=None;отказ=None;начало=time.perf_counter_ns()
        with mock.patch.object(читатель,'_прочитать_поток',side_effect=с_дописыванием):
            try: _,наблюдение=модуль.прочитать_живой_префикс(пример.источник,позднее.примеры.КОРЕНЬ,контекст)
            except ValueError as ошибка: отказ=str(ошибка)
        длительность=time.perf_counter_ns()-начало
        assert len(разборы)==1 and пример.источник.read_bytes()==исходное+позднее.примеры.байты(событие)
        поля=('попытки','сырых_байтов','хэширование_нс','хвост_нс','байты_хвоста','строки_хвоста')
        return {'длительность_нс':длительность,'разборы':разборы,'отказ':отказ,
            'метрики':None if наблюдение is None else {к:наблюдение[к] for к in поля},
            'исходные_байты':len(исходное),'исходный_sha256':хэш(исходное),
            'дописанные_байты':len(позднее.примеры.байты(событие))}
    finally: пример.doCleanups()


def профиль_дописывания(прежний, выход, раунды):
    import основание_двусторонней_координации as новый
    описание=importlib.util.spec_from_file_location('прежнее_основание',прежний)
    модуль=importlib.util.module_from_spec(описание);описание.loader.exec_module(модуль)
    коды={'прежний':хэш(Path(прежний).read_bytes()),'новый':хэш(Path(новый.__file__).read_bytes())}
    образцы=[]
    for номер in range(раунды):
        for вариант in (['прежний','новый'] if номер%2==0 else ['новый','прежний']):
            результат=образец_дописывания(модуль if вариант=='прежний' else новый)
            assert (результат['отказ']=='LIVE изменился при чтении') if вариант=='прежний' else результат['отказ'] is None
            образцы.append({'раунд':номер+1,'вариант':вариант,**результат})
    assert len({образец['исходный_sha256'] for образец in образцы})==1
    assert коды=={'прежний':хэш(Path(прежний).read_bytes()),'новый':хэш(Path(новый.__file__).read_bytes())}
    итог={'схема':'fum.профиль-дописывания-LIVE.1','образцы':образцы,'хэши_кода':коды,
        'медианы_нс':{в:statistics.median(образец['длительность_нс'] for образец in образцы if образец['вариант']==в)
            for в in ['прежний','новый']},'версия_интерпретатора':platform.python_version(),
        'границы':'AB/BA на одинаковом ограниченном RAW и реальном append после независимого разбора. Setup/cleanup исключены; кэш ОС не сбрасывался. Метрики чтения логические, физический I/O неизвестен. Это профиль читателя, не всей .4 и не Desktop-доставки. Старый отказ и новый успех не дают коэффициента ускорения.'}
    выход.write_text(json.dumps(итог,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'образцов':len(образцы),'медианы_нс':итог['медианы_нс'],
        'хэш_результата':хэш(выход.read_bytes())},ensure_ascii=False))


def главная():
    парсер=argparse.ArgumentParser(description=__doc__,allow_abbrev=False)
    парсер.add_argument('--выход',required=True);парсер.add_argument('--раунды',type=int,default=3)
    парсер.add_argument('--прежний-код')
    параметры=парсер.parse_args(); assert 1<=параметры.раунды<=7
    выход=Path(параметры.выход);assert выход.is_absolute() and not выход.exists() and выход.parent.is_dir()
    if параметры.прежний_код:
        профиль_дописывания(параметры.прежний_код,выход,параметры.раунды);return
    каталог=Path(__file__).resolve().parents[1]
    исходники=[каталог/'scripts/подготовка_дочернего_поручения.py',каталог/'scripts/основание_двусторонней_координации.py',
        Path(__file__).resolve(),каталог/'tests/test_подготовки_дочернего_поручения.py',каталог/'tests/test_основания_двусторонней_координации.py']
    манифест={п.relative_to(каталог).as_posix():хэш(п.read_bytes()) for п in исходники}
    результаты=[]
    for номер in range(параметры.раунды):
        for вариант in (['прежний','координация'] if номер%2==0 else ['координация','прежний']):
            assert манифест=={п.relative_to(каталог).as_posix():хэш(п.read_bytes()) for п in исходники}
            результаты.append(образец(вариант))
    assert манифест=={п.relative_to(каталог).as_posix():хэш(п.read_bytes()) for п in исходники}
    медианы={}
    for вариант in ['прежний','координация']:
        строки=[з for з in результаты if з['вариант']==вариант]
        медианы[вариант]={имя:statistics.median(з[имя] for з in строки) for имя in
            ['план_нс','приглашение_нс','применение_нс']}
        if вариант=='координация': медианы[вариант]['основание_нс']=statistics.median(з['основание_нс'] for з in строки)
    итог={'схема':'fum.профиль-основания-координации.1','образцы':результаты,'медианы_нс':медианы,
        'хэши_кода':манифест,'версия_интерпретатора':platform.python_version(),
        'версия_гита':subprocess.check_output(['git','--version'],text=True).strip(),
        'границы':'Настоящие малые Git/native-фикстуры; setup/cleanup и сериализация исключены. Кэш ОС не сбрасывался. Импортированные зависимости и физический I/O не замкнуты этим манифестом. Живое создание чата, подтверждение ребёнка и полный цикл ROOT не измерены.',
        'решение_по_оптимизации':'Сохранён штатный заранее проверенный кэш, без скрытого повторного JSON-разбора. Новый объём проверяет происхождение и RAW. Данных о выгоде дополнительной оптимизации нет; ускорение не утверждается.'}
    выход.write_text(json.dumps(итог,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'образцов':len(результаты),'медианы_нс':медианы,'хэш_результата':хэш(выход.read_bytes())},ensure_ascii=False))

if __name__=='__main__': главная()

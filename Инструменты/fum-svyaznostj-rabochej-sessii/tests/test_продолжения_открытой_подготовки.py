def адрес(путь):
    return {'путь': str(путь), 'sha256': hashlib.sha256(Path(путь).read_bytes()).hexdigest()}


class ОткрытаяФикстура:
    def __init__(сам, владелец, *, контур='обычный'):
        сам.ф = база.КорневаяФикстура(владелец, контур=контур)
        сам.м = importlib.import_module('повторная_подготовка_этапа')
        сам.корень = сам.ф.корень
        сам.п = сам.ф.п
        сам.готовность = сам.м.коммит.готовность.путь_этапа(сам.п)
        правильные = copy.deepcopy(сам.ф.вход['проверки'])
        сам.ф.вход['проверки'][0]['аргументы'] = [sys.executable, '-B', '-c', 'raise SystemExit(7)']
        старый_вход = сам.ф.сохранить('старый-фасад.json', сам.ф.вход)
        план = сам.ф.м.построить_план(сам.ф.вход)
        старый_план = сам.ф.сохранить('старый-план.json', план)
        старый_план.chmod(0o400)
        итог = сам.ф.м.выполнить(сам.ф.вход, план, сам.м.хэш(сам.м.байты(план)))
        if итог['код'] != 7 or сам.готовность.exists() or not Path(сам.п['подготовка']).exists():
            raise AssertionError(('Отказ seed не достигнут', итог))
        # Заранее разрешённое private рабочее место; ready остаётся отсутствующим.
        сам.готовность.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        сам.старые = сам.м.манифест(сам.корень, сам.п['запрос'])
        if len(сам.старые) != 1:
            raise AssertionError('Нужна одна настоящая failed v4')
        предыдущий = сам.ф.ф.запрос
        текст = предыдущий.read_text()
        начало = текст.index('## Повлиял на файлы\n') + len('## Повлиял на файлы\n')
        конец = текст.index('<!-- FUM-MD-RECENCY:BEGIN -->') if '<!-- FUM-MD-RECENCY:BEGIN -->' in текст else len(текст)
        # Исходная повреждённая фикстура: production исправляет её только updater.
        предыдущий.write_text(текст[:начало] + '\n<!-- FUM-КАРТОЧКА:НАЧАЛО состав -->\n'
            '- [мёртвая будущая проверка](материалы/запуски-проверок/99_00000000-0000-0000-0000-000000000099.json)\n'
            '<!-- FUM-КАРТОЧКА:КОНЕЦ состав -->\n\n' + текст[конец:])
        номера = [str(uuid.uuid4()), str(uuid.uuid4())]
        номер = max(э['порядок'] for э in сам.старые) + 1
        будущие = [str(Path(сам.п['запрос']).parent / 'материалы/запуски-проверок' / f'{н}_{и}.json')
            for н, и in enumerate(номера, номер)]
        существующие = [ц for ц in сам.п['разрешённые_цели'] if (сам.корень / ц).exists()]
        прежний_отчёт = предыдущий.with_name('отчёт.md').relative_to(сам.корень).as_posix()
        существующие += [прежний_отчёт]
        цели = существующие + будущие
        выходы = {к: str(сам.ф.приватный / ('новый-' + к + '.json')) for к in сам.м.ВЫХОДЫ}
        наполнение = copy.deepcopy(сам.ф.наполнение)
        наполнение['разрешение'] = {'путь': выходы['разрешение'], 'sha256': сам.м.хэш(сам.м.байты(цели))}
        наполнение['ожидаемые_цели'] = будущие
        составы = []
        for н, запрос in enumerate([сам.п['запрос'], предыдущий.relative_to(сам.корень).as_posix()]):
            разрешение = {'схема': 'fum.разрешение-состава-карточки.1', 'задача': сам.п['задача'],
                'запрос': запрос, 'корень': str(сам.корень), 'ветка': сам.п['ветка'],
                'исходный_коммит': сам.п['исходный_коммит'], 'разрешённые_цели': существующие,
                'ожидаемые_цели': []}
            путь = сам.корень / запрос
            составы.append({'запрос': запрос, 'sha256': сам.м.хэш(путь.read_bytes()),
                'режим': путь.stat().st_mode & 0o777,
                'план': str(сам.ф.приватный / f'состав-план-{н}.json'),
                'разрешение': адрес(сам.ф.сохранить(f'состав-{н}.json', разрешение))})
        for н, проверка in enumerate(правильные, номер):
            проверка.update(идентификатор=номера[н-номер], порядок=н)
        модель = сам.корень / сам.п['история_модели']
        курсор = Path(сам.п['кэш_модели'])
        сам.вход = {'схема': 'fum.продолжение-открытой-подготовки-ROOT.1',
            'прежняя_подготовка': адрес(сам.п['подготовка']), 'прежний_вход': адрес(старый_вход),
            'прежний_план': адрес(старый_план), 'новые_выходы': выходы,
            'новые_проверки': правильные, 'новая_связность': {'идентификатор': номера[-1], 'порядок': номер+len(правильные)},
            'новый_состав': цели, 'наполнение': адрес(сам.ф.сохранить('выбранное-наполнение.json', наполнение)),
            'составы': составы, 'закрепления': {'HEAD': сам.п['исходный_коммит'], 'ref': сам.п['ветка'],
                'родители': сам.п['родители'], 'v4': сам.старые,
                'источник_модели': {**адрес(сам.п['источник_модели']), 'режим': Path(сам.п['источник_модели']).stat().st_mode & 0o777},
                'история_модели': {'sha256': сам.м.хэш(модель.read_bytes()), 'режим': модель.stat().st_mode & 0o777},
                'курсор_модели': {'sha256': сам.м.хэш(курсор.read_bytes()), 'режим': курсор.stat().st_mode & 0o777}}}
        сам.защищённые = {п: п.read_bytes() for п in [модель, курсор, предыдущий.with_name('отчёт.md'),
            *[сам.корень / э['путь'] for э in сам.старые]]}

    def план(сам):
        return сам.м.построить_план_продолжения(сам.вход)

    def выполнить(сам, план=None, **параметры):
        план = сам.план() if план is None else план
        return сам.м.выполнить(сам.вход, план, сам.м.хэш(сам.м.байты(план)), **параметры)


class ПродолжениеОткрытойПодготовки(unittest.TestCase):
    def test_прерывание_родителя_сохраняет_текущие_каналы_и_длительность(сам, *, отказ_синхронизации=False,
            проверить_публикацию=False, отказ_наблюдателя=False):
        with tempfile.TemporaryDirectory(prefix='fum-проверка-прерывания-') as каталог:
            место = Path(каталог); маркер = место / 'worker.json'; выход = место / 'профиль.json'
            публикация = место / 'публикация.json'; завершение = место / 'завершение.json'
            работник = место / 'работник.py'; контроллер = место / 'контроллер.py'
            связь_чтения, связь_записи = os.pipe(); барьер_чтения, барьер_записи = os.pipe()
            вывод = b'partial stdout\n'; ошибки = b'partial stderr\n'
            работник.write_text('import json,os,select,signal,sys\n'
                'def сохранить(путь,данные):\n'
                ' временный=путь+".tmp"\n'
                ' with os.fdopen(os.open(временный,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600),"w") as ф:\n'
                '  ф.write(json.dumps(данные)); ф.flush(); os.fsync(ф.fileno())\n'
                ' os.replace(временный,путь)\n'
                'signal.signal(signal.SIGINT,lambda номер,кадр:sys.exit(130))\n'
                f'sys.stdout.buffer.write({вывод!r}); sys.stdout.buffer.flush()\n'
                f'sys.stderr.buffer.write({ошибки!r}); sys.stderr.buffer.flush()\n'
                'try:\n'
                f' рабочий={str(маркер)!r}+".tmp"\n'
                ' with os.fdopen(os.open(рабочий,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600),"w") as ф:\n'
                f'  сохранить({str(публикация)!r},{{"pid":os.getpid()}})\n'
                f'  готовые,_,_=select.select([{связь_чтения},{барьер_чтения}],[],[])\n'
                f'  if {связь_чтения} in готовые and os.read({связь_чтения},1)==b"": raise SystemExit(0)\n'
                f'  if {барьер_чтения} in готовые and os.read({барьер_чтения},1)!=b"1": raise SystemExit(0)\n'
                '  ф.write(json.dumps({"pid":os.getpid()})); ф.flush(); os.fsync(ф.fileno())\n'
                f' os.replace(рабочий,{str(маркер)!r})\n'
                f' os.read({связь_чтения},1)\n'
                'finally:\n'
                f' сохранить({str(завершение)!r},{{"pid":os.getpid()}})\n')
            контроллер.write_text('import sys,tempfile\n'
                f'sys.path.insert(0,{str(Path(__file__).resolve().parent)!r})\n'
                'import профиль_продолжения_открытой_подготовки as профиль\n'
                'профиль.старый_профиль.снимок_замыкания=lambda:{}\n'
                'профиль.версии=lambda:{}\n'
                f'tempfile.tempdir={str(место)!r}\n'
                'каталог_сырых=tempfile.mkdtemp\n'
                f'tempfile.mkdtemp=lambda *а,**п:каталог_сырых(*а,**{{**п,"dir":{str(место)!r}}})\n'
                'настоящий=профиль.subprocess.Popen\n'
                'def запустить(аргументы,*а,**п):\n'
                ' if "--исполнитель-образца" in аргументы:\n'
                f'  аргументы=[sys.executable,"-B",{str(работник)!r}]\n'
                f'  п.update(close_fds=True,pass_fds=({связь_чтения},{барьер_чтения}))\n'
                ' return настоящий(аргументы,*а,**п)\n'
                'профиль.subprocess.Popen=запустить\n'
                + ('настоящая_синхронизация=профиль.os.fsync\nсчётчик=[0]\n'
                    'def синхронизировать(дескриптор):\n счётчик[0]+=1\n'
                    ' if счётчик[0]==1: raise OSError("Отказ fsync текущего stdout")\n'
                    ' return настоящая_синхронизация(дескриптор)\n'
                    'профиль.os.fsync=синхронизировать\n' if отказ_синхронизации else '')
                + 'обработчик=профиль.signal.getsignal(профиль.signal.SIGINT)\n'
                f'sys.argv=[профиль.__file__,"--выход",{str(выход)!r},"--повторы","1"]\n'
                'код=профиль.главный()\n'
                'assert профиль.signal.getsignal(профиль.signal.SIGINT)==обработчик\n'
                'raise SystemExit(код)\n')
            работник.chmod(0o600); контроллер.chmod(0o600)
            процесс = None; идентификатор_работника = None
            try:
                процесс = subprocess.Popen([sys.executable, '-B', str(контроллер)], stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE, start_new_session=True, close_fds=True,
                    pass_fds=(связь_чтения, барьер_чтения))
                os.close(связь_чтения); связь_чтения = None
                os.close(барьер_чтения); барьер_чтения = None
                if проверить_публикацию or отказ_наблюдателя:
                    предел = time.monotonic() + 10
                    while not публикация.exists() and процесс.poll() is None and time.monotonic() < предел:
                        time.sleep(0.02)
                    сам.assertTrue(публикация.exists(), 'worker не достиг барьера публикации')
                    сам.assertIsNone(идентификатор_работника)
                    if отказ_наблюдателя: raise RuntimeError('Отказ наблюдателя до чтения процесса')
                    сам.assertFalse(маркер.exists(), 'Финальное имя предъявлено до записи JSON')
                os.write(барьер_записи, b'1')
                предел = time.monotonic() + 10
                while not маркер.exists() and процесс.poll() is None and time.monotonic() < предел:
                    time.sleep(0.02)
                сам.assertTrue(маркер.exists(), 'worker не достиг измеряемого ожидания')
                идентификатор_работника = json.loads(маркер.read_bytes())['pid']
                os.kill(процесс.pid, signal.SIGINT)
                вывод_контроллера, ошибки_контроллера = процесс.communicate(timeout=15)
                сам.assertEqual(1, процесс.returncode, (вывод_контроллера, ошибки_контроллера))
                итог = json.loads(выход.read_bytes())
                сам.assertEqual([], итог['результаты']); сам.assertEqual([], итог['принятые_пары'])
                сам.assertEqual([], итог['итоги']); сам.assertEqual(1, len(итог['отказы']))
                отказ = итог['отказы'][0]
                сам.assertEqual((130, 'KeyboardInterrupt', 'целый процесс образца'),
                    (отказ['код'], отказ['тип'], отказ['стадия']))
                сам.assertIsInstance(отказ['полный_процесс_нс'], int)
                сам.assertGreater(отказ['полный_процесс_нс'], 0)
                сам.assertEqual({'stdout.bin': {'sha256': hashlib.sha256(вывод).hexdigest(), 'байтов': len(вывод)},
                    'stderr.bin': {'sha256': hashlib.sha256(ошибки).hexdigest(), 'байтов': len(ошибки)}}, отказ['сохранённые_каналы'])
                сам.assertEqual(отказ_синхронизации, bool(отказ['ошибки_сохранения']))
                сам.assertEqual(not отказ_синхронизации, отказ['синхронизация_каналов']['stdout.bin'])
                сам.assertTrue(отказ['синхронизация_каналов']['stderr.bin'])
                сохранённые = list(место.glob('fum-профиль-сырые-*')); сам.assertEqual(1, len(сохранённые))
                for имя, сырые in [('stdout.bin', вывод), ('stderr.bin', ошибки)]:
                    файл = сохранённые[0] / имя
                    сам.assertEqual(сырые, файл.read_bytes()); сам.assertEqual(0o600, файл.stat().st_mode & 0o777)
            finally:
                for дескриптор in (связь_записи, барьер_записи, связь_чтения, барьер_чтения):
                    if дескриптор is not None: os.close(дескриптор)
                if процесс is not None:
                    try: процесс.communicate(timeout=15)
                    except subprocess.TimeoutExpired:
                        процесс.send_signal(signal.SIGINT)
                        try: процесс.communicate(timeout=10)
                        except subprocess.TimeoutExpired: процесс.kill(); процесс.communicate(timeout=5)
                    if публикация.exists():
                        идентификатор_для_уборки = json.loads(публикация.read_bytes())['pid']
                        try:
                            сам.assertTrue(завершение.exists(), 'Нет атомарного свидетельства выхода worker')
                            сам.assertEqual(идентификатор_для_уборки, json.loads(завершение.read_bytes())['pid'])
                            сам.assertEqual(0o600, завершение.stat().st_mode & 0o777)
                            with сам.assertRaises(ProcessLookupError): os.kill(идентификатор_для_уборки, 0)
                        finally:
                            try: os.kill(идентификатор_для_уборки, signal.SIGKILL)
                            except ProcessLookupError: pass


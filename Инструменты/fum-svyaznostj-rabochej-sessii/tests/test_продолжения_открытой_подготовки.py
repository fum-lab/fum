    def test_живые_коммит_и_ветка_сверяются_до_чтения_истории(сам):
        for вид in ('HEAD', 'ref'):
            with сам.subTest(дрейф=вид):
                ф = ОткрытаяФикстура(сам)
                if вид == 'HEAD':
                    ф.ф.ф.гит('commit', '--allow-empty', '-m', 'Дрейф HEAD фикстуры')
                else:
                    ф.ф.ф.гит('branch', 'codex/ранний-дрейф')
                    ф.ф.ф.гит('symbolic-ref', 'HEAD', 'refs/heads/codex/ранний-дрейф')
                индекс = (ф.корень / '.git/index').read_bytes()
                with patch.object(ф.м.фасад, 'история', side_effect=AssertionError('Прочитана зависимая история')) as история:
                    with сам.assertRaises(ValueError): ф.план()
                    история.assert_not_called()
                сам.assertEqual(индекс, (ф.корень / '.git/index').read_bytes())
                сам.assertFalse(any(Path(п).exists() for п in ф.вход['новые_выходы'].values()))
                for путь, сырые in ф.защищённые.items(): сам.assertEqual(сырые, путь.read_bytes())

    def test_отказ_до_готовности_исправляет_аргументы_и_оба_состава(сам):
        ф = ОткрытаяФикстура(сам)
        план = ф.план()
        итог = ф.выполнить(план)
        сам.assertEqual(0, итог['код'], итог)
        параметры = план['технические_входы']['коммит']
        готовность = ф.м.коммит.готовность.прочитать(ф.м.коммит.готовность.путь_этапа(параметры), параметры)
        сам.assertEqual((0, 1, []), (готовность['активное'], len(готовность['поколения']), готовность['отзывы']))
        for путь, байты in ф.защищённые.items(): сам.assertEqual(байты, путь.read_bytes())
        сам.assertFalse(Path(параметры['квитанция']).exists())
        сам.assertEqual(ф.п['исходный_коммит'], ф.ф.ф.гит('rev-parse', 'HEAD').strip())


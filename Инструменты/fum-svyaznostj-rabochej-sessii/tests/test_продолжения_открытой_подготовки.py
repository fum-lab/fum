    def test_именованный_канал_исторического_отчёта_отказывает_до_чтения(сам):
        ф = ОткрытаяФикстура(сам); план = ф.план()
        отчёт = (ф.корень / ф.вход['составы'][1]['запрос']).with_name('отчёт.md')
        режим = отчёт.stat().st_mode & 0o777
        настоящий = ф.м.фасад.исполнить_команду; прочитать = Path.read_bytes
        чтения = []
        def выполнить(а, корень):
            итог = настоящий(а, корень)
            if 'подготовить-повтор' in а and итог['код'] == 0:
                отчёт.unlink(); os.mkfifo(отчёт, режим); отчёт.chmod(режим)
            return итог
        def чтение(путь):
            if путь == отчёт and not путь.is_file():
                чтения.append(путь)
                raise AssertionError('Чтение FIFO до проверки типа файла')
            return прочитать(путь)
        with patch.object(ф.м.фасад, 'исполнить_команду', side_effect=выполнить), \
                patch.object(Path, 'read_bytes', чтение):
            итог = ф.выполнить(план)
        сам.assertEqual(1, итог['код'])
        сам.assertEqual([], чтения)
        сам.assertTrue(Path(ф.вход['новые_выходы']['подготовка']).is_file())
        сам.assertFalse(Path(ф.вход['составы'][0]['план']).exists())

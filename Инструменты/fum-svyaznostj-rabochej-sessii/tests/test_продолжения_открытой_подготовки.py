    def test_дрейф_до_эффекта_не_пишет_выходы_и_маркер(сам):
        ф = ОткрытаяФикстура(сам); план = ф.план()
        файлы = [ф.корень / ф.старые[0]['путь'], Path(ф.п['кэш_модели']),
            ф.корень / ф.п['история_модели'], Path(ф.п['подготовка']),
            ф.корень / ф.вход['составы'][1]['запрос']]
        индекс = (ф.корень / '.git/index').read_bytes()
        for файл in файлы:
            сырые = файл.read_bytes(); режим = файл.stat().st_mode & 0o777
            for способ in ('байты', 'режим'):
                with сам.subTest(файл=файл.name, способ=способ):
                    if способ == 'байты': файл.write_bytes(сырые + b'\n')
                    else: файл.chmod(0o400 if режим != 0o400 else 0o600)
                    with сам.assertRaises(ф.м.ОШИБКИ): ф.выполнить(план)
                    сам.assertFalse(Path(план['полный_результат']).exists())
                    сам.assertFalse(any(Path(п).exists() for п in ф.вход['новые_выходы'].values()))
                    сам.assertEqual(индекс, (ф.корень / '.git/index').read_bytes())
                    файл.chmod(0o600); файл.write_bytes(сырые); файл.chmod(режим)

"""Исправление после отказа сохраняет границу и первоначальный возраст."""
import copy
import unittest

import test_готовность_этапа as основа
import поколения_готовности as поколения


class ПоколенияГотовности(unittest.TestCase):
    def setUp(сам):
        пример = основа.ГотовностьЭтапа(); пример.setUp()
        сам.снимок = copy.deepcopy(пример.снимок)
        сам.старый = сам.снимок["проверки"][0]
        сам.новый = "00000000-0000-0000-0000-000000000009"
        сам.записи = [[сам.старый, "e" * 64]]
        сам.время = 100_000_000_000
        сам.состояние = поколения.объявить("/фикстура", сам.снимок, сам.записи, сам.время, 600)

    def новый_снимок(сам):
        снимок = copy.deepcopy(сам.снимок)
        снимок["проверки"] = [сам.новый]
        снимок["отпечаток_содержимого"] = "f" * 64
        return снимок

    def test_отзыв_и_повторная_готовность_не_обнуляют_возраст(сам):
        старый = copy.deepcopy(сам.состояние)
        отозвано = поколения.отозвать(старый, 0, "Отказ формата отчёта", сам.время + 650_000_000_000)
        _, решение = поколения.оценить(отозвано, сам.снимок, сам.время + 650_000_000_001)
        сам.assertFalse(решение["фиксировать_этап"])
        новое = поколения.объявить("/фикстура", сам.новый_снимок(), сам.записи + [[сам.новый, "a" * 64]],
            сам.время + 660_000_000_000, 600, прежнее=отозвано, замены={сам.старый: сам.новый})
        сам.assertEqual(старый["поколения"][0], новое["поколения"][0])
        сам.assertEqual(1, новое["активное"])
        сам.assertEqual(сам.время, новое["готов_в_наносекундах_эпохи"])
        _, решение = поколения.оценить(новое, сам.новый_снимок(), сам.время + 500_000_000_000)
        сам.assertTrue(решение["фиксировать_этап"] and решение["задержка"])

    def test_переобъявление_требует_отзыва(сам):
        with сам.assertRaises(ValueError):
            поколения.объявить("/фикстура", сам.новый_снимок(), сам.записи + [[сам.новый, "a" * 64]],
                сам.время + 1, 600, прежнее=сам.состояние, замены={сам.старый: сам.новый})

    def test_повтор_не_размножает_поколения_и_отзывы(сам):
        повтор = поколения.объявить("/фикстура", сам.снимок, сам.записи, сам.время + 1, 600, прежнее=сам.состояние)
        сам.assertEqual(1, len(повтор["поколения"]))
        один = поколения.отозвать(повтор, 0, "Исправление", сам.время + 2)
        два = поколения.отозвать(один, 0, "Исправление", сам.время + 3)
        сам.assertEqual(один["отзывы"], два["отзывы"])

    def test_поздняя_команда_и_новая_цель_не_проникают_в_исправление(сам):
        отозвано = поколения.отозвать(сам.состояние, 0, "Исправление", сам.время + 1)
        for поле, значение in [("экземпляры", "d" * 64), ("разрешённые_цели", "новая-работа.swift")]:
            снимок = сам.новый_снимок(); снимок[поле].append(значение)
            with сам.subTest(поле=поле), сам.assertRaises(ValueError):
                поколения.объявить("/фикстура", снимок, сам.записи + [[сам.новый, "a" * 64]],
                    сам.время + 2, 600, прежнее=отозвано, замены={сам.старый: сам.новый})

    def test_проверки_нельзя_заменить_без_явного_соответствия(сам):
        отозвано = поколения.отозвать(сам.состояние, 0, "Исправление", сам.время + 1)
        with сам.assertRaises(ValueError):
            поколения.объявить("/фикстура", сам.новый_снимок(), сам.записи + [[сам.новый, "a" * 64]],
                сам.время + 2, 600, прежнее=отозвано)

    def test_прежние_записи_проверок_нельзя_переписать(сам):
        отозвано = поколения.отозвать(сам.состояние, 0, "Исправление", сам.время + 1)
        with сам.assertRaises(ValueError):
            поколения.объявить("/фикстура", сам.новый_снимок(), [[сам.старый, "b" * 64], [сам.новый, "a" * 64]],
                сам.время + 2, 600, прежнее=отозвано, замены={сам.старый: сам.новый})

    def test_дрейф_и_остановка_не_разрешают_фиксацию(сам):
        _, дрейф = поколения.оценить(сам.состояние, сам.новый_снимок(), сам.время + 1)
        _, стоп = поколения.оценить(сам.состояние, сам.снимок, сам.время + 1, остановлено=True)
        сам.assertFalse(дрейф["фиксировать_этап"] or стоп["фиксировать_этап"])

def снимок(р):
    """Вся фикстура, включая private inputs, Git и пространство READY."""
    корень = р.ф.каталог
    результат = {}
    for путь in [корень, *корень.rglob('*')]:
        мета = путь.lstat()
        данные = (
            путь.read_bytes() if stat.S_ISREG(мета.st_mode)
            else os.readlink(путь) if stat.S_ISLNK(мета.st_mode)
            else None
        )
        результат[путь.relative_to(корень).as_posix()] = (
            мета.st_dev, мета.st_ino, мета.st_mode, мета.st_uid,
            мета.st_gid, мета.st_nlink, мета.st_size,
            мета.st_mtime_ns, мета.st_ctime_ns, данные)
    return результат



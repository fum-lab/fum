@contextlib.contextmanager
def наблюдать(модуль, имя, корень):
    """Обёртки выполняют исходный вызов ровно один раз."""
    код = getattr(модуль, имя).__code__
    журнал = модуль.журнал()
    класс = журнал.ИндексПутей
    исходный_путь = журнал.точный_путь
    исходная_проверка = класс.проверить
    исходное_перечисление = Path.iterdir
    собственный = [False]
    данные = {
        'свой': [0, 0], 'прочие': [0, 0],
        'пути': [], 'индексы': [], 'проверенные': [],
    }

    @contextlib.contextmanager
    def область(значение):
        прежнее = собственный[0]
        собственный[0] = значение
        try:
            yield
        finally:
            собственный[0] = прежнее

    def точный(корень, путь, *аргументы, **поля):
        прямой = sys._getframe(1).f_code is код
        if прямой:
            данные['пути'].append((путь, поля.get('индекс')))
        with область(прямой):
            return исходный_путь(корень, путь, *аргументы, **поля)

    def создать(*аргументы, **поля):
        прямой = sys._getframe(1).f_code is код
        with область(прямой):
            индекс = класс(*аргументы, **поля)
        if прямой:
            данные['индексы'].append(индекс)
        return индекс

    def проверить(индекс):
        прямой = any(индекс is и for и in данные['индексы'])
        if прямой:
            данные['проверенные'].append(индекс)
        with область(прямой):
            return исходная_проверка(индекс)

    def перечислить(каталог):
        исходные = исходное_перечисление(каталог)
        if каталог != корень / 'Журнал':
            return исходные
        счётчик = данные['свой' if собственный[0] else 'прочие']
        счётчик[0] += 1

        def выдать():
            for путь in исходные:
                счётчик[1] += 1
                yield путь

        return выдать()

    with mock.patch.object(Path, 'iterdir', перечислить), \
            mock.patch.object(журнал, 'точный_путь', точный), \
            mock.patch.object(журнал, 'ИндексПутей', создать), \
            mock.patch.object(класс, 'проверить', проверить):
        yield данные



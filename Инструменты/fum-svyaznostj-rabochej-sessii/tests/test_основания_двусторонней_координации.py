КОРЕНЬ = '00000000-0000-0000-0000-000000000177'

def байты(данные):
    return (json.dumps(данные, ensure_ascii=False)+'\n').encode()

def сообщение(текст, номер, виды=None):
    return {'type':'response_item','payload':{'type':'message','role':'user','id':'msg_'+str(номер),
        'content':[{'type':'input_text','text':текст}],
        'internal_chat_message_metadata_passthrough':{'content_item_kinds':виды or ['user.text']}}}

class ОснованиеКоординации(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory(); сам.addCleanup(сам.временный.cleanup)

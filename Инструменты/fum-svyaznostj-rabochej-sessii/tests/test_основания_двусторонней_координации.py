            файл_оригинала=сам.папка/(э['экземпляр']+'.raw');позиция=э['позиция'];файл_оригинала.write_bytes(сам.источник.read_bytes()[позиция['начало']:позиция['конец']]);файл_оригинала.chmod(0o600)

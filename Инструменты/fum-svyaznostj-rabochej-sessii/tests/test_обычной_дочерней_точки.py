    def test_независимый_вход_нужен_до_любой_записи_и_при_повторе(сам):
        сам.отказ_без_эффекта(lambda: сам.коммит.подготовить(сам.параметры))
        сам.отказ_без_эффекта(lambda: сам.коммит.подготовить(сам.параметры,
            доверенное_поручение=dict(сам.выбор, sha256='0' * 64)))
        сам.готовить()
        путь = Path(сам.параметры['подготовка'])
        for действие in [lambda: сам.коммит.объявить_готовность(путь, [база.ЗАПУСК], 600),
                lambda: сам.коммит.отозвать_готовность(путь, 0, 'Отзыв'),
                lambda: сам.коммит.создать(путь, [база.ЗАПУСК])]:
            сам.отказ_без_эффекта(действие)
        сам.создать()
        сам.отказ_без_эффекта(lambda: сам.коммит.создать(путь, [база.ЗАПУСК]))

    def test_изменение_нативного_потока_после_готовности_и_последнего_допуска_отказывает(сам):
        сам.готовить()
        исходные = сам.нативный.read_bytes()
        сам.нативные_записи[1]['timestamp'] = '2026-10-01T00:00:01Z'
        сам.сохранить_нативный()
        сам.отказ_без_эффекта(сам.создать)
        сам.нативный.write_bytes(исходные)
        сверить = сам.коммит.готовность.сверить
        def подменить_после_допуска(*аргументы, **параметры):
            итог = сверить(*аргументы, **параметры)
            сам.сохранить_нативный()
            return итог
        with mock.patch.object(сам.коммит.готовность, 'сверить', side_effect=подменить_после_допуска):
            сам.отказ_без_эффекта(сам.создать)
        сам.assertFalse(Path(сам.параметры['квитанция']).exists())

    def test_история_и_цели_вне_акта_не_дают_модельной_записи(сам):
        прежние = copy.deepcopy(сам.параметры)
        for поле, значение in [('история_модели', 'Планирование/модель.json'),
                ('разрешённые_цели', [*сам.параметры['разрешённые_цели'], 'чужое.txt'])]:
            сам.параметры[поле] = значение
            сам.отказ_без_эффекта(сам.подготовить)
            сам.параметры.clear()
            сам.параметры.update(copy.deepcopy(прежние))
        сам.assertFalse(Path(сам.параметры['сообщение']).exists())


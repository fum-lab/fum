import unittest
from unittest import mock

import test_создание_коммита as база

ИСПОЛНИТЕЛЬ = '00000000-0000-0000-0000-000000000003'


class ОбычнаяДочерняяТочка(unittest.TestCase):
    def setUp(сам):
        сам.фикстура = база.СозданиеКоммита()
        сам.фикстура.setUp()
        сам.addCleanup(сам.фикстура.doCleanups)
        сам.коммит = база.коммит
        сам.параметры = сам.фикстура.параметры
        постановка = сам.фикстура.корень / 'Планирование/постановка.md'
        постановка.parent.mkdir()
        постановка.write_text('Сохранить ограниченную контрольную точку.\n')
        сам.фикстура.гит('add', 'Планирование/постановка.md')
        сам.фикстура.гит('commit', '-qm', 'Закрепить начальную постановку')
        начальный = сам.фикстура.гит('rev-parse', 'HEAD').strip()
        сам.нативный = сам.фикстура.каталог / 'дочерний.jsonl'
        сам.поручение = 'Выполни закреплённую постановку в своей области.\n'
        сам.нативные_записи = [
            {'type': 'session_meta', 'payload': {'id': ИСПОЛНИТЕЛЬ,
                'cwd': str(сам.фикстура.корень), 'thread_source': 'agent_created_thread',
                'git': {'commit_hash': начальный}}},
            {'type': 'turn_context', 'timestamp': '2026-10-01T00:00:00Z',
                'payload': {'cwd': str(сам.фикстура.корень), 'model': 'gpt-6.1-sol', 'effort': 'ultra'}},
            {'type': 'response_item', 'payload': {'type': 'function_call_output', 'name': 'create_thread',
                'output': '<codex_delegation>\n  <source_thread_id>' + база.ЗАДАЧА +
                '</source_thread_id>\n  <input>' + сам.поручение + '</input>\n</codex_delegation>'}},
        ]
        сам.сохранить_нативный()
        сам.акт = {'схема': 'fum.поручение-дочерней-контрольной-точки.1',
            'координатор': база.ЗАДАЧА, 'исполнитель': ИСПОЛНИТЕЛЬ,
            'ветка': сам.параметры['ветка'],
            'область': ['данные.txt', 'Журнал/README.md', str(Path(база.ЗАПРОС).parent) + '/',
                'Инструменты/реестр-системных-приложений-и-инструментов.md'],
            'постановка': {'коммит': начальный, 'путь': 'Планирование/постановка.md',
                'sha256': hashlib.sha256(постановка.read_bytes()).hexdigest()},
            'хэш_нативного_поручения': hashlib.sha256(сам.поручение.encode()).hexdigest()}
        файл_акта = сам.фикстура.корень / 'Планирование/обычное-поручение.json'
        файл_акта.write_text(json.dumps(сам.акт, ensure_ascii=False) + '\n')
        сам.фикстура.гит('add', 'Планирование/обычное-поручение.json')
        сам.фикстура.гит('commit', '-qm', 'Закрепить обычного исполнителя')
        голова = сам.фикстура.гит('rev-parse', 'HEAD').strip()
        сам.выбор = {'координатор': база.ЗАДАЧА, 'исполнитель': ИСПОЛНИТЕЛЬ,
            'коммит': голова, 'путь': 'Планирование/обычное-поручение.json',
            'sha256': hashlib.sha256(файл_акта.read_bytes()).hexdigest()}
        снимок = база.прочитать_сообщения(сам.фикстура.источник, база.ЗАДАЧА,
            корень_репозитория=сам.фикстура.корень, без_записи=True)
        сам.параметры.update(схема='fum.создание-коммита.7', исполнитель=ИСПОЛНИТЕЛЬ,
            выбранное_поручение=сам.выбор, исходный_коммит=голова, родители=[голова],
            источник_модели=str(сам.нативный))
        сам.параметры['источники'][0]['граница_снимка'] = {
            'граница': снимок['граница'], 'sha256': снимок['sha256'], 'неоднозначные_экземпляры': []}
        сам.среда = mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ИСПОЛНИТЕЛЬ})
        сам.среда.start()
        сам.addCleanup(сам.среда.stop)

    def сохранить_нативный(сам):
        сам.нативный.write_text(''.join(json.dumps(запись, ensure_ascii=False) + '\n'
            for запись in сам.нативные_записи))

    def подготовить(сам, **параметры):
        return сам.коммит.подготовить(сам.параметры, доверенное_поручение=сам.выбор, **параметры)

    def готовить(сам):
        сам.подготовить()
        сам.проверить_данные()
        return сам.коммит.объявить_готовность(Path(сам.параметры['подготовка']), [база.ЗАПУСК], 600,
            доверенное_поручение=сам.выбор)

    def проверить_данные(сам):
        сам.фикстура.гит('add', '.')
        with contextlib.redirect_stdout(io.StringIO()):
            код = сам.фикстура.отчёты.выполнить_запуск(сам.фикстура.корень, сам.фикстура.запрос,
                'Проверить данные обычного исполнителя', 'фикстура', база.ЗАПУСК, 15,
                [sys.executable, '-c', "from pathlib import Path; assert Path('данные.txt').read_text() == 'проверено\\n'"],
                класс_проверки='адресная', приёмочные_раунды=True)
            сам.assertEqual(0, код)
            сам.фикстура.отчёты.выполнить_предпросмотр(сам.фикстура.корень, сам.фикстура.запрос)
        сам.фикстура.гит('add', str(Path(база.ЗАПРОС).parent))

    def сохранить_приватный_вход(сам, имя, данные):
        путь = сам.фикстура.каталог / имя
        путь.write_bytes(сам.коммит.байты(данные))
        путь.chmod(0o600)
        return str(путь)

    def вызвать_команду(сам, *аргументы, успешна=True, профиль=None, стадия=None):
        начало = time.perf_counter_ns()
        процесс = subprocess.run(сам.фикстура.команда_CLI(*аргументы), cwd=сам.фикстура.корень,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=30)
        длительность = time.perf_counter_ns() - начало
        сам.assertEqual(0 if успешна else 2, процесс.returncode, процесс.stderr.decode())
        данные = json.loads(процесс.stdout if успешна else процесс.stderr)
        if not успешна:
            сам.assertEqual('fum.отказ-создания-коммита.1', данные['схема'])
            сам.assertGreater(данные['длительность_наносекунды'], 0)
            сам.assertFalse(данные['повтор_автоматически'])
        if профиль is not None:
            профиль.append({'стадия': стадия, 'длительность_наносекунды': длительность})
        return данные

    def снимок_без_эффекта(сам):
        пути = [сам.фикстура.корень / сам.параметры['история_модели'],
            Path(сам.параметры['квитанция']),
            *sorted((сам.фикстура.каталог / 'готовность').rglob('*'))]
        return (сам.фикстура.гит('rev-parse', 'HEAD'),
            (сам.фикстура.корень / '.git/index').read_bytes(),
            {str(путь): путь.read_bytes() if путь.is_file() else None for путь in пути})

    def отказ_команды(сам, *аргументы):
        до = сам.снимок_без_эффекта()
        сам.вызвать_команду(*аргументы, успешна=False)
        сам.assertEqual(до, сам.снимок_без_эффекта())

    def выполнить_цикл_команд(сам, профиль=None):
        вход = сам.сохранить_приватный_вход('вход.json', сам.параметры)
        выбор = сам.сохранить_приватный_вход('выбор.json', сам.выбор)
        доверие = ['--доверенное-поручение', выбор]
        сам.вызвать_команду('подготовить', '--вход', вход, *доверие)
        сам.проверить_данные()
        готовность = сам.вызвать_команду('готово', '--подготовка', сам.параметры['подготовка'],
            '--проверка', база.ЗАПУСК, '--предел-секунд', '600', *доверие,
            профиль=профиль, стадия='готовность')
        файл = Path(готовность['путь'])
        прежнее = файл.read_bytes()
        for поле in ('сообщение', 'подготовка', 'квитанция'):
            сам.параметры[поле] = str(сам.фикстура.каталог / ('повтор-' + поле + '.json'))
        вход = сам.сохранить_приватный_вход('вход-повтор.json', сам.параметры)
        сам.вызвать_команду('подготовить-повтор', '--вход', вход, *доверие)
        сам.assertEqual(прежнее, файл.read_bytes())
        аргументы = ['создать', '--подготовка', сам.параметры['подготовка'], '--проверка', база.ЗАПУСК, *доверие]
        первый = сам.вызвать_команду(*аргументы, профиль=профиль, стадия='первое создание')
        квитанция = Path(сам.параметры['квитанция']).read_bytes()
        после_создания = файл.read_bytes()
        сам.assertEqual(json.loads(прежнее)['готовность']['готов_в_наносекундах_эпохи'],
            json.loads(после_создания)['готовность']['готов_в_наносекундах_эпохи'])
        второй = сам.вызвать_команду(*аргументы, профиль=профиль, стадия='повторное чтение')
        сам.assertEqual(первый, второй)
        сам.assertEqual(квитанция, Path(сам.параметры['квитанция']).read_bytes())
        сам.assertEqual(после_создания, файл.read_bytes())
        сам.assertEqual('1', сам.фикстура.гит('rev-list', '--count', сам.параметры['исходный_коммит'] + '..HEAD').strip())
        сырой = сам.фикстура.гит('cat-file', 'commit', первый['коммит'])
        сам.assertIn('FUM Интегратор [gpt-6.1-sol; effort=ultra]', сырой)
        сам.assertTrue(сырой.endswith('Codex-Thread-ID: ' + база.ЗАДАЧА + '\n'))
        стадии = {пункт['стадия'] for пункт in json.loads(квитанция)['профиль']}
        сам.assertIn('последняя сверка обычного поручения', стадии)
        сам.assertIn('последняя сверка модели исполнителя', стадии)
        return json.loads(квитанция)

    def создать(сам, выбор=None):
        return сам.коммит.создать(Path(сам.параметры['подготовка']), [база.ЗАПУСК],
            доверенное_поручение=сам.выбор if выбор is None else выбор)

    def отказ_без_эффекта(сам, действие):
        голова = сам.фикстура.гит('rev-parse', 'HEAD')
        индекс = (сам.фикстура.корень / '.git/index').read_bytes()
        история = сам.фикстура.корень / сам.параметры['история_модели']
        до = история.read_bytes() if история.exists() else None
        with сам.assertRaises(сам.коммит.ОшибкаКоммита):
            действие()
        сам.assertEqual(голова, сам.фикстура.гит('rev-parse', 'HEAD'))
        сам.assertEqual(индекс, (сам.фикстура.корень / '.git/index').read_bytes())
        сам.assertEqual(до, история.read_bytes() if история.exists() else None)


ОШИБКИ = (RuntimeError, ValueError, OSError, TypeError)


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


class ЧтениеЦепочкиПодготовки(unittest.TestCase):
    def setUp(сам):
        сам.ф = переход.ПроверкиПереходаМеждуВетками('runTest')
        сам.ф.setUp()
        сам.addCleanup(сам.ф.doCleanups)
        сам.корень = сам.ф.корень
        сам.приватный = сам.ф.фикстура.root / 'выбор-читателя'
        сам.приватный.mkdir(mode=0o700)
        сам.вызовы = []

    def гит(сам, корень, *аргументы):
        сам.assertEqual(str(сам.корень), str(корень), 'callback ограничен собственным корнем')
        разрешённые = {
            ('rev-parse', '--show-toplevel'),
            ('rev-parse', '--absolute-git-dir'),
            ('rev-parse', '--path-format=absolute', '--git-common-dir'),
            ('symbolic-ref', '-q', 'HEAD'),
            ('worktree', 'list', '--porcelain'),
            ('show', сам.база + ':.gitmodules'),
            ('ls-tree', '-r', '-z', сам.база),
        }
        проверка_предка = (len(аргументы) == 4
            and аргументы[:2] == ('merge-base', '--is-ancestor')
            and all(type(объект) is str and re.fullmatch('[0-9a-f]{40}', объект)
                for объект in аргументы[2:]))
        сам.assertTrue(аргументы in разрешённые or проверка_предка, аргументы)
        сам.вызовы.append((str(корень), аргументы))
        среда = {к: з for к, з in os.environ.items() if not к.startswith('GIT_')}
        return subprocess.check_output(['git', '--no-optional-locks',
            '-c', 'core.hooksPath=/dev/null', '-c', 'core.fsmonitor=false',
            '-C', str(сам.корень), *аргументы], env=среда, stderr=subprocess.PIPE)

    def срез(сам):
        return (сам.ф.срез(), исполнить_гит('--no-optional-locks', 'status', '--porcelain=v1',
            '--untracked-files=all', cwd=сам.корень))

    def описать(сам, результат):
        сам.поколение = Path(результат['квитанция'])
        снимок = сам.ф.модуль.снять_снимок(сам.корень)
        сам.админ = Path(снимок['гит_каталог'])
        сам.ветка, сам.база = снимок['ссылка'], снимок['коммит']
        сам.описание = {'схема': 'fum.выбор-чтения-зависимостей.2',
            'корень': str(сам.корень), 'коммит': сам.база,
            'исполнитель': сам.ф.исполнитель, 'координатор': сам.ф.задача,
            'описание_sha256': хэш((сам.корень / '.gitmodules').read_bytes()),
            'квитанция_sha256': хэш(сам.поколение.read_bytes()),
            'квитанция_путь': сам.поколение.relative_to(сам.админ).as_posix(),
            'зависимости': [{'путь': сам.ф.фикстура.path, 'секция': сам.ф.фикстура.path,
                'ревизия': сам.ф.фикстура.first_revision,
                'форк': str(сам.ф.фикстура.fork), 'оригинал': str(сам.ф.фикстура.upstream)}]}
        сам.файл_выбора = сам.приватный / 'описание-выбора.json'
        сам.сохранить_выбор()

    def сохранить_выбор(сам):
        сам.файл_выбора.write_bytes(байты(сам.описание))
        сам.файл_выбора.chmod(0o600)
        сам.выбор = {'путь': str(сам.файл_выбора), 'sha256': хэш(сам.файл_выбора.read_bytes())}

    def создать_цепочку(сам, *, смешанная=False, с_набором=False):
        сам.ф.подготовить_процессом()
        if смешанная:
            старый = хэш(сам.ф.квитанция().read_bytes())
            снимок = сам.ф.следующая_граница()
            итог = прежние.ПроверкиНовогоЭтапа.перейти_через_команду(сам.ф, снимок, старый)
            сам.assertEqual(0, итог.returncode, итог.stderr + итог.stdout)
            сам.ф.подготовить_процессом()
        набор = None
        if с_набором:
            сам.набор_графов = сам.приватный / 'пустой-набор-графов.json'
            сам.набор_графов.write_bytes(байты({'схема': 'fum.набор-графов-зависимостей.1', 'графы': {}}))
            сам.набор_графов.chmod(0o600)
            набор = {'путь': str(сам.набор_графов), 'хэш_байтов': хэш(сам.набор_графов.read_bytes())}
            старый = хэш(сам.ф.квитанция().read_bytes())
            снимок = сам.ф.следующая_граница()
            команда = [sys.executable, '-I', '-S', '-B', сам.ф.модуль.__file__]
            общие = ['--корень-репозитория', str(сам.корень), '--снимок', str(сам.ф.файл_снимка(снимок)),
                '--исполнитель', сам.ф.исполнитель, '--корневая-задача', сам.ф.задача,
                '--набор-графов', набор['путь'], '--ожидаемый-хэш-набора-графов', набор['хэш_байтов']]
            for этап, опции in [('новая-попытка', ['--ожидаемый-хэш-квитанции', старый]), ('подготовить', [])]:
                итог = subprocess.run([*команда, этап, *общие, *опции], start_new_session=True,
                    capture_output=True, text=True, timeout=60)
                сам.assertEqual(0, итог.returncode, итог.stderr + итог.stdout)
        сам.исходные_байты = сам.ф.квитанция().read_bytes()
        исполнить_гит('switch', '-c', 'codex/выбранный-читатель', cwd=сам.корень)
        снимок = сам.ф.модуль.снять_снимок(сам.корень)
        итог = сам.ф.перейти_процессом(снимок, хэш(сам.исходные_байты), набор=набор)
        сам.assertEqual(0, итог.returncode, итог.stderr + итог.stdout)
        сам.описать(json.loads(итог.stdout))
        сам.assertEqual(сам.исходные_байты, сам.ф.квитанция().read_bytes())

    def допустить(сам, выбор=None):
        return читатель.допустить_чтение_цепочки(сам.выбор if выбор is None else выбор,
            корень=сам.корень, исходный_коммит=сам.база, ветка=сам.ветка,
            исполнитель=сам.ф.исполнитель, корневая_задача=сам.ф.задача, гит=сам.гит)

    def сверить_без_процессов(сам, допуск):
        with mock.patch.object(subprocess, 'Popen', side_effect=AssertionError('процесс при читающей повторной сверке')):
            with mock.patch.object(os, 'killpg', side_effect=AssertionError('проверка группы при читающей повторной сверке')):
                with mock.patch.object(сам, 'гит', side_effect=AssertionError('Git при читающей повторной сверке')):
                    return читатель.сверить_чтение_цепочки(допуск)

    def отказать(сам, допуск=None):
        до = сам.срез()
        with сам.assertRaises(ОШИБКИ):
            сам.допустить() if допуск is None else сам.сверить_без_процессов(допуск)
        сам.assertEqual(до, сам.срез())


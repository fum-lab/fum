    def test_16_публичные_факты_выводятся_из_подлинного_допуска(сам):
        сам.создать_цепочку()
        допуск = сам.допустить()
        до = сам.срез()
        with mock.patch.object(subprocess, 'Popen', side_effect=AssertionError('процесс из accessor')):
            факты = читатель.получить_факты_зависимостей(допуск)
        сам.assertIs(type(факты), tuple)
        сам.assertEqual(1, len(факты))
        запись = факты[0]
        выбранная = сам.описание['зависимости'][0]
        сам.assertEqual(str(сам.корень / выбранная['путь']), запись.корень)
        сам.assertEqual(str(сам.админ / 'modules' / выбранная['секция']), запись.гит_каталог)
        for поле in ('путь', 'секция', 'ревизия', 'форк', 'оригинал'):
            сам.assertEqual(выбранная[поле], getattr(запись, поле))
        сам.assertEqual((('rev-parse', 'HEAD'), ('rev-parse', '--show-toplevel'),
            ('status', '--porcelain', '--untracked-files=all', '--ignore-submodules=none'),
            ('rev-parse', '--verify', 'HEAD'), ('ls-tree', '-r', '-z', выбранная['ревизия'])), запись.формы_гит)
        with сам.assertRaises((AttributeError, TypeError)):
            запись.корень = '/чужой'
        for подделка in (None, {}, object.__new__(читатель.ДопускЧтенияЦепочки)):
            with сам.assertRaises(ОШИБКИ):
                читатель.получить_факты_зависимостей(подделка)
        сам.assertEqual(до, сам.срез())
        указатель = сам.корень / выбранная['путь'] / '.git'
        указатель.write_text('gitdir: ' + str(сам.админ) + '\n')
        до = сам.срез()
        with сам.assertRaises(ОШИБКИ):
            читатель.получить_факты_зависимостей(допуск)
        with сам.assertRaises(ОШИБКИ):
            сам.допустить()
        сам.assertEqual(до, сам.срез())


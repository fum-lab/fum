"""Страница не скрывает старый остаток, поздний ввод или повреждение."""
import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from компактный_остаток import представить


def снимок():
    сообщения = []
    for номер, текст in enumerate(("Сделай.\n", "Сделай.\n", "Отмени первую команду.\n")):
        сообщения.append({"экземпляр": hashlib.sha256(str(номер).encode()).hexdigest(),
            "позиция": {"начало": номер * 100, "конец": (номер + 1) * 100, "sha256": "a" * 64},
            "происхождение": "человек", "содержимое": [{"type": "input_text", "text": текст}],
            "сырой_объект": {"историческая_нагрузка": "я" * 20000}, "дубли": []})
    экземпляры = [запись["экземпляр"] for запись in сообщения]
    return {"схема": "fum.остаток-сообщений.1", "задача": "00000000-0000-0000-0000-000000000177",
        "источник": "b" * 64, "история_sha256": "c" * 64,
        "контекст": {"граница": 300, "sha256": "d" * 64, "экземпляры": экземпляры},
        "сообщения": сообщения,
        "остаток": [{"экземпляр": экземпляр, "причины": ["нет записи обработки"],
            "поздние": экземпляры[номер + 1:], "последняя_обработка": None}
            for номер, экземпляр in enumerate(экземпляры)],
        "полнота_источника": True, "неполный_хвост": 0, "непроверенный_хвост": 0,
        "граница_заключительной_сверки": 300, "разбор_сообщений_завершён": False,
        "завершение_задачи_доказано": False, "профиль": {}}


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, indent=2) + "\n").encode()


class ПроверкаКомпактногоОстатка(unittest.TestCase):
    def показать(проверка, значение=None, **параметры):
        данные = байты(снимок() if значение is None else значение)
        return представить(данные, hashlib.sha256(данные).hexdigest(), **параметры)

    def test_повторы_и_поздняя_отмена_сохраняются_дословно(проверка):
        исходный = снимок()
        результат = проверка.показать(исходный)
        проверка.assertEqual([запись["оригинал"] for запись in результат["сообщения"]],
            [{ключ: запись[ключ] for ключ in ("экземпляр", "позиция", "происхождение", "содержимое")}
                for запись in исходный["сообщения"]])
        проверка.assertEqual(результат["всего_необработанных"], 3)
        проверка.assertFalse(результат["завершение_задачи_доказано"])

    def test_страница_не_погашает_старый_пропуск(проверка):
        результат = проверка.показать(начало=2, число=1)
        проверка.assertEqual(результат["сообщения"][0]["оригинал"]["содержимое"][0]["text"], "Отмени первую команду.\n")
        проверка.assertEqual(результат["всего_необработанных"], 3)
        проверка.assertEqual(результат["непоказанных_необработанных"], 2)
        проверка.assertFalse(результат["показаны_все_сообщения"])
        проверка.assertIsNone(результат["следующее_начало"])

    def test_неполнота_и_неизвестное_происхождение_остаются_видимыми(проверка):
        исходный = снимок()
        исходный["полнота_источника"] = False
        исходный["непроверенный_хвост"] = 27
        исходный["сообщения"][2]["происхождение"] = "неясно"
        исходный["остаток"][2]["причины"].append("происхождение не подтверждено")
        результат = проверка.показать(исходный, начало=2)
        проверка.assertFalse(результат["состояние"]["полнота_источника"])
        проверка.assertEqual(результат["состояние"]["непроверенный_хвост"], 27)
        проверка.assertEqual(результат["сообщения"][0]["причины"], исходный["остаток"][2]["причины"])

    def test_обработанный_поздний_ввод_тоже_доступен(проверка):
        исходный = снимок()
        исходный["остаток"] = исходный["остаток"][:1]
        результат = проверка.показать(исходный, начало=2)
        проверка.assertEqual(len(результат["сообщения"]), 1)
        проверка.assertEqual(результат["непоказанных_необработанных"], 1)
        проверка.assertEqual(результат["сообщения"][0]["причины"], [])

    def test_хэш_фиксирует_весь_артефакт(проверка):
        данные = байты(снимок())
        with проверка.assertRaisesRegex(ValueError, "хэш"):
            представить(данные, "0" * 64)

    def test_неизвестная_схема_и_дубли_отклоняются(проверка):
        for изменение in ("схема", "экземпляр", "ссылка"):
            исходный = снимок()
            if изменение == "схема":
                исходный["схема"] = "fum.остаток-сообщений.999"
            elif изменение == "экземпляр":
                исходный["сообщения"][1]["экземпляр"] = исходный["сообщения"][0]["экземпляр"]
            else:
                исходный["остаток"][0]["поздние"].append("f" * 64)
            with проверка.subTest(изменение=изменение), проверка.assertRaises(ValueError):
                проверка.показать(исходный)

    def test_размер_и_границы_не_дают_молчаливого_усечения(проверка):
        for параметры in ({"начало": -1}, {"число": 0}, {"начало": 4}, {"максимум_байтов": 100}):
            with проверка.subTest(параметры=параметры), проверка.assertRaises(ValueError):
                проверка.показать(**параметры)

    def test_вложения_не_сводятся_к_одному_тексту(проверка):
        исходный = снимок()
        исходный["сообщения"][0]["содержимое"].append({"type": "input_image", "image_url": "data:image/png;base64,AA=="})
        результат = проверка.показать(исходный, число=1)
        проверка.assertEqual(результат["сообщения"][0]["оригинал"]["содержимое"], исходный["сообщения"][0]["содержимое"])

    def test_указатели_достигают_точных_данных_без_их_повторения(проверка):
        результат = проверка.показать(число=1)
        запись = результат["сообщения"][0]
        проверка.assertEqual(запись["указатель_оригинала"], "/сообщения/0")
        проверка.assertEqual(запись["указатель_обработки"], "/остаток/0")
        проверка.assertEqual(запись["число_поздних"], 2)
        проверка.assertNotIn("поздние", запись)
        проверка.assertEqual(результат["следующее_начало"], 1)

    def test_неоднозначные_части_читателя_сохраняются_на_любой_странице(проверка):
        for содержимое in (None, "неструктурированный текст", {"text": "неизвестная форма"}):
            for начало in (0, 2):
                исходный = снимок()
                исходный["сообщения"][0]["содержимое"] = содержимое
                исходный["сообщения"][0]["происхождение"] = "неоднозначный"
                исходный["полнота_источника"] = False
                исходный["остаток"][0]["причины"].append("происхождение не подтверждено")
                with проверка.subTest(содержимое=содержимое, начало=начало):
                    результат = проверка.показать(исходный, начало=начало, число=1)
                    проверка.assertFalse(результат["состояние"]["полнота_источника"])
                    проверка.assertEqual(результат["причины_всего"]["происхождение не подтверждено"], 1)
                    if начало == 0:
                        проверка.assertEqual(результат["сообщения"][0]["оригинал"]["содержимое"], содержимое)

    def test_командный_вход_не_пишет_файлов_и_не_выдаёт_частичный_успех(проверка):
        данные = байты(снимок())
        with tempfile.TemporaryDirectory() as каталог:
            путь = Path(каталог) / "полный.json"
            путь.write_bytes(данные)
            команда = [sys.executable, "-B", str(Path(__file__).resolve().parents[1] / "scripts/показать-остаток.py"),
                "--результат", str(путь), "--sha256", hashlib.sha256(данные).hexdigest()]
            исход = subprocess.run(команда, capture_output=True)
            проверка.assertEqual(исход.returncode, 0, исход.stderr)
            проверка.assertEqual(json.loads(исход.stdout)["всего_необработанных"], 3)
            отказ = subprocess.run(команда + ["--максимум-байтов", "100"], capture_output=True)
            проверка.assertEqual(отказ.returncode, 2)
            проверка.assertEqual(отказ.stdout, b"")
            проверка.assertIn("бюджет", отказ.stderr.decode())
            проверка.assertEqual(list(Path(каталог).iterdir()), [путь])
            проверка.assertEqual(путь.read_bytes(), данные)

    def test_повтор_ключа_JSON_не_подменяет_состояние(проверка):
        данные = байты(снимок())
        данные = данные.replace('"полнота_источника": true'.encode(),
            '"полнота_источника": false, "полнота_источника": true'.encode())
        with проверка.assertRaisesRegex(ValueError, "повтор поля"):
            представить(данные, hashlib.sha256(данные).hexdigest())

"""Измерить один живой сеанс и повторные независимые страницы на открытом входе."""
import argparse
import copy
import hashlib
import io
import json
import statistics
import sys
import time
import tracemalloc
from pathlib import Path

from test_живые_страницы_остатка import снимок, строка
from компактный_остаток import (
    вести_живые_страницы,
    закодировать,
    описать_живой_сеанс,
    представить_живое,
    семантический_хэш,
)


def открытый_снимок(число=600):
    значение = снимок()
    образец = значение["сообщения"][0]
    сообщения = []
    for номер in range(число):
        сообщение = copy.deepcopy(образец)
        сообщение["экземпляр"] = hashlib.sha256(f"живой-экземпляр-{номер}".encode()).hexdigest()
        сообщение["позиция"] = {
            "начало": номер * 100,
            "конец": (номер + 1) * 100,
            "sha256": "a" * 64,
        }
        сообщение["содержимое"] = [{"type": "input_text", "text": f"Команда {номер}.\n"}]
        сообщение["сырой_объект"] = {"номер": номер, "нагрузка": "открытая фикстура " * 40}
        сообщение["дубли"] = []
        сообщения.append(сообщение)
    экземпляры = [сообщение["экземпляр"] for сообщение in сообщения]
    значение["сообщения"] = сообщения
    значение["контекст"].update({"экземпляры": экземпляры, "граница": число * 100})
    значение["граница_заключительной_сверки"] = число * 100
    значение["остаток"] = [{
        "экземпляр": экземпляр,
        "причины": ["нет записи обработки"],
        "поздние": экземпляры[номер + 1:],
        "последняя_обработка": None,
    } for номер, экземпляр in enumerate(экземпляры)]
    значение["профиль"] = {"фикстура": "не входит в семантический SHA"}
    return значение


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    параметры = разбор.parse_args()
    if параметры.выход.exists():
        raise SystemExit("выход профиля уже существует")

    значение = открытый_снимок()
    снимок_sha256 = семантический_хэш(значение)
    запросы = "".join((
        строка({"схема": "fum.запрос-страницы-живого-остатка.1",
            "снимок_sha256": снимок_sha256, "начало": 0, "число": 10,
            "максимум_байтов": 256 * 1024}),
        строка({"схема": "fum.запрос-страницы-живого-остатка.1",
            "снимок_sha256": снимок_sha256, "начало": 590, "число": 10,
            "максимум_байтов": 256 * 1024}),
        строка({"схема": "fum.завершение-сеанса-живых-страниц.1",
            "снимок_sha256": снимок_sha256}),
    ))

    def описание():
        return закодировать(описать_живой_сеанс(значение))

    def один_сеанс():
        выход = io.StringIO()
        код = вести_живые_страницы(значение, io.StringIO(запросы), выход,
            источник_перепроверен=True)
        assert код == 3
        return выход.getvalue().encode("utf-8")

    def независимые_страницы():
        return b"".join((
            закодировать(представить_живое(значение, снимок_sha256,
                начало=0, число=10, максимум_байтов=256 * 1024)),
            закодировать(представить_живое(значение, снимок_sha256,
                начало=590, число=10, максимум_байтов=256 * 1024)),
        ))

    функции = {
        "описание": описание,
        "один_сеанс_две_страницы": один_сеанс,
        "две_независимые_страницы": независимые_страницы,
    }
    замеры = {имя: [] for имя in функции}
    выходы = {}
    имена = tuple(функции)
    for повтор in range(5):
        порядок = имена if повтор % 2 == 0 else tuple(reversed(имена))
        for имя in порядок:
            начало = time.perf_counter_ns()
            выходы[имя] = функции[имя]()
            замеры[имя].append(time.perf_counter_ns() - начало)
    память = {}
    for имя, функция in функции.items():
        tracemalloc.start()
        функция()
        память[имя] = tracemalloc.get_traced_memory()[1]
        tracemalloc.stop()

    ответы = [json.loads(линия) for линия in выходы["один_сеанс_две_страницы"].splitlines()]
    assert [ответ["схема"] for ответ in ответы] == [
        "fum.сеанс-живых-страниц-остатка.1",
        "fum.страница-живого-остатка.1",
        "fum.страница-живого-остатка.1",
    ]
    assert [ответ["начало"] for ответ in ответы[1:]] == [0, 590]
    каталог = Path(__file__).resolve().parents[1]
    исходники = {имя: hashlib.sha256((каталог / имя).read_bytes()).hexdigest() for имя in (
        "scripts/компактный_остаток.py",
        "scripts/обработать-сообщения-задачи.py",
        "tests/test_живые_страницы_остатка.py",
        "tests/профиль_живых_страниц_остатка.py",
    )}
    результат = {
        "схема": "fum.профиль-живых-страниц-остатка.1",
        "Python": sys.version.split()[0],
        "снимок_sha256": снимок_sha256,
        "исходники_sha256": исходники,
        "всего_сообщений": len(значение["сообщения"]),
        "всего_поздних_ссылок": sum(len(запись["поздние"]) for запись in значение["остаток"]),
        "страницы": [{"начало": 0, "число": 10}, {"начало": 590, "число": 10}],
        "повторы": 5,
        "длительности_наносекунды": замеры,
        "медианы_наносекунды": {имя: statistics.median(значения) for имя, значения in замеры.items()},
        "пиковые_байты_Python": память,
        "выходные_байты": {имя: len(выход) for имя, выход in выходы.items()},
        "выходные_sha256": {имя: hashlib.sha256(выход).hexdigest() for имя, выход in выходы.items()},
        "семантическая_сверка": True,
        "граница": "Один неизменный открытый снимок из 600 сообщений и 179700 поздних ссылок. Подготовка фикстуры и команд исключена; в измерение входят проверка снимка, семантический SHA и сериализация ответа. Пять пар чередуют порядок. Память Python измерена отдельно. Это не измерение RSS, токенов, чтения исходного JSONL или смысловой обработки сообщений.",
    }
    параметры.выход.parent.mkdir(parents=True, exist_ok=True)
    параметры.выход.write_bytes(закодировать(результат))
    print(json.dumps({ключ: результат[ключ] for ключ in (
        "медианы_наносекунды", "пиковые_байты_Python", "выходные_байты", "семантическая_сверка")},
        ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    выполнить()

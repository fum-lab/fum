def отпечаток(байты):
    return hashlib.sha256(байты).hexdigest()


def пример(метка='альфа', дата='2026-10-10_10-00-00_MSK'):
    задача = '00000000-0000-4000-8000-000000000001'
    исходник = {'коммит': '1' * 40, 'путь': 'Журнал/основание/запрос.md', 'sha256': '2' * 64}
    текст = 'Повтор\n\n```\nданные с ё\n'
    команда = {'задача': задача, 'экземпляр': '3' * 64,
        'снимок': {'sha256': '4' * 64, 'байты': 200},
        'позиция': {'начало': 0, 'конец': 100, 'sha256': '5' * 64},
        'текст': текст, 'sha256_текста': отпечаток(текст.encode())}
    отчёт = 'Содержательный отчёт.\n'
    return {'схема': 'fum.независимая-пара-журнала.1', 'узел': 'fum-lab/fum',
        'корневая_задача': задача, 'писатель': '00000000-0000-4000-8000-000000000002',
        'основание': исходник, 'журнал': дата + '_' + метка, 'заголовок': 'Этап ' + метка,
        'первоначальный_запрос': copy.deepcopy(исходник), 'предыдущий_этап': None,
        'команды': [команда], 'отчёт': {'текст': отчёт, 'sha256': отпечаток(отчёт.encode())}}


def запись(пара, вход, формат='fum.независимая-пара-журнала.1'):
    return {'идентификатор': пара['идентификатор'], 'формат': формат,
        'журнал': вход['журнал'], 'заголовок': вход['заголовок'],
        'файлы': [{к: ф[к] for к in ('путь', 'sha256', 'режим')} for ф in пара['файлы']],
        'приёмка': {'коммит': '6' * 40, 'путь': 'Планирование/приёмка.json', 'sha256': '7' * 64}}


def состав(записи):
    значение = {'схема': 'fum.состав-независимого-журнала.1', 'записи': записи}
    канон = {**значение, 'записи': sorted(записи, key=lambda з: з['журнал'])}
    хэш = отпечаток(json.dumps(канон, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode())
    return значение, хэш


class НезависимаяПараИИндекс(unittest.TestCase):
    def test_дословные_команды_и_точный_повтор(сам):
        вход = пример(); прежний = copy.deepcopy(вход)
        второй = copy.deepcopy(вход['команды'][0]); второй['экземпляр'] = '8' * 64
        второй['позиция']['начало'] = 100; второй['позиция']['конец'] = 200
        вход['команды'].append(второй)
        пара = построить_пару(вход)
        сам.assertEqual(пара, построить_пару(copy.deepcopy(вход)))
        сам.assertEqual(вход['команды'][0], прежний['команды'][0])
        сам.assertFalse(пара['разрешение_установки'])
        сам.assertEqual(len(пара['файлы']), 2)
        сам.assertEqual(пара['файлы'][0]['байты'].count(вход['команды'][0]['текст'].encode()), 2)
        for файл in пара['файлы']:
            сам.assertEqual(файл['sha256'], отпечаток(файл['байты']))
        сам.assertNotIn('Следующий запрос', пара['файлы'][0]['байты'].decode())

    def test_закрытые_поля_и_неизвестная_версия(сам):
        for изменение in ({'схема': 'неизвестна'}, {'лишнее': True}, {'писатель': True}):
            with сам.subTest(изменение=изменение), сам.assertRaises(ValueError):
                построить_пару({**пример(), **изменение})
        вход = пример(); del вход['отчёт']
        with сам.assertRaises(ValueError): построить_пару(вход)

    def test_подмена_дословного_текста_и_отчёта(сам):
        for поле in ('команды', 'отчёт'):
            вход = пример(); цель = вход['команды'][0] if поле == 'команды' else вход['отчёт']
            цель['текст'] += 'подмена'
            with сам.subTest(поле=поле), сам.assertRaises(ValueError): построить_пару(вход)

    def test_повторный_экземпляр_порядок_и_граница(сам):
        for нарушение in ('повтор', 'порядок', 'граница', 'чужая задача'):
            вход = пример(); вторая = copy.deepcopy(вход['команды'][0])
            if нарушение != 'повтор': вторая['экземпляр'] = '8' * 64
            if нарушение == 'порядок': вторая['позиция']['начало'] = 50
            if нарушение == 'граница': вторая['позиция']['конец'] = 201
            if нарушение == 'чужая задача': вторая['задача'] = вход['писатель']
            вход['команды'].append(вторая)
            with сам.subTest(нарушение=нарушение), сам.assertRaises(ValueError): построить_пару(вход)

    def test_опасные_пути_и_невозможное_время(сам):
        for имя in ('../побег', '2026-02-30_10-00-00_MSK_этап', '2026-10-10_10-00-00_MSK_этап/дочерний'):
            with сам.subTest(имя=имя), сам.assertRaises(ValueError):
                построить_пару({**пример(), 'журнал': имя})

    def _поколение(сам):
        старое_имя = '2026-07-02_11-14-15_MSK'
        старые_файлы = []
        for имя, текст in (('запрос.md', '# Исторический запрос\n\nИсходная команда.\n'),
                           ('отчёт.md', '# Исторический отчёт\n\nСохранённый результат.\n')):
            байты = текст.encode()
            старые_файлы.append({'путь': 'Журнал/' + старое_имя + '/' + имя,
                'байты': байты, 'sha256': отпечаток(байты), 'режим': 0o644})
        входы = [{'журнал': старое_имя, 'заголовок': 'Историческая запись'},
            пример('бета', '2026-10-11_10-00-00_MSK')]
        пары = [{'идентификатор': '9' * 64, 'файлы': старые_файлы}, построить_пару(входы[1])]
        записи = [запись(п, в) for п, в in zip(пары, входы)]
        # Это синтетические исторические байты и реальная форма старого имени.
        # Индекс проверяет состав/хэши; допуск старого формата остаётся снаружи.
        записи[0]['формат'] = 'fum.прежняя-пара-журнала.1'
        файлы = {ф['путь']: ф['байты'] for п in пары for ф in п['файлы']}
        return входы, пары, записи, файлы

    def test_перестановка_смешанного_набора(сам):
        _, _, записи, файлы = сам._поколение(); вход, хэш = состав(записи)
        результат = построить_индекс(вход, файлы, ожидаемый_sha256=хэш)
        обратный, тот_же = состав(list(reversed(записи)))
        сам.assertEqual(хэш, тот_же)
        сам.assertEqual(результат, построить_индекс(обратный, dict(reversed(list(файлы.items()))), ожидаемый_sha256=тот_же))
        сам.assertFalse(результат['разрешение_установки'])

    def test_пропуск_лишний_файл_и_подмена_обоих_поколений(сам):
        _, _, записи, файлы = сам._поколение(); вход, хэш = состав(записи)
        for имя in файлы:
            for нарушение in ('пропуск', 'подмена'):
                изменённые = dict(файлы)
                if нарушение == 'пропуск': del изменённые[имя]
                else: изменённые[имя] += b'x'
                with сам.subTest(имя=имя, нарушение=нарушение), сам.assertRaises(ValueError):
                    построить_индекс(вход, изменённые, ожидаемый_sha256=хэш)
        with сам.assertRaises(ValueError):
            построить_индекс(вход, {**файлы, 'Журнал/лишний.md': b'x'}, ожидаемый_sha256=хэш)

    def test_повтор_идентичности(сам):
        _, _, записи, файлы = сам._поколение()
        записи[1]['идентификатор'] = записи[0]['идентификатор']
        вход, хэш = состав(записи)
        with сам.assertRaisesRegex(ValueError, 'повтор ID записи'):
            построить_индекс(вход, файлы, ожидаемый_sha256=хэш)

    def test_коллизия_регистра_двух_допустимых_новых_имён(сам):
        входы = [пример('ёлка'), пример('ЁЛКА')]
        пары = [построить_пару(в) for в in входы]
        вход, хэш = состав([запись(п, в) for п, в in zip(пары, входы)])
        файлы = {ф['путь']: ф['байты'] for п in пары for ф in п['файлы']}
        with сам.assertRaisesRegex(ValueError, 'коллизия имени записи'):
            построить_индекс(вход, файлы, ожидаемый_sha256=хэш)

    def test_устаревший_состав_и_индекс(сам):
        _, _, записи, файлы = сам._поколение(); вход, хэш = состав(записи)
        полный = построить_индекс(вход, файлы, ожидаемый_sha256=хэш)
        старый, прежний = состав(записи[:1])
        старые_файлы = {ф['путь']: файлы[ф['путь']] for ф in записи[0]['файлы']}
        сжатый = построить_индекс(старый, старые_файлы, ожидаемый_sha256=прежний)
        сам.assertNotEqual(полный['байты'], сжатый['байты'])
        with сам.assertRaises(ValueError): построить_индекс(вход, файлы, ожидаемый_sha256=прежний)

    def test_вставка_между_датами_не_меняет_прежние_пары(сам):
        _, пары, записи, файлы = сам._поколение(); до = copy.deepcopy((пары, файлы))
        вход = пример('вставка', '2026-10-10_11-00-00_MSK'); новая = построить_пару(вход)
        поколение, хэш = состав([*записи, запись(новая, вход)])
        полный = {**файлы, **{ф['путь']: ф['байты'] for ф in новая['файлы']}}
        построить_индекс(поколение, полный, ожидаемый_sha256=хэш)
        сам.assertEqual((пары, файлы), до)

    def test_нет_чтения_и_эффектов(сам):
        вход = пример(); пара = построить_пару(вход)
        поколение, хэш = состав([запись(пара, вход)])
        файлы = {ф['путь']: ф['байты'] for ф in пара['файлы']}
        with patch('builtins.open', side_effect=AssertionError('ФС')), patch('subprocess.run', side_effect=AssertionError('процесс')), patch('time.time', side_effect=AssertionError('время')):
            сам.assertEqual(пара, построить_пару(вход))
            сам.assertFalse(построить_индекс(поколение, файлы, ожидаемый_sha256=хэш)['разрешение_установки'])

    def test_историческое_имя_не_ослабляет_новый_формат(сам):
        _, _, записи, файлы = сам._поколение()
        записи[0]['формат'] = 'fum.независимая-пара-журнала.1'
        вход, хэш = состав(записи)
        with сам.assertRaises(ValueError): построить_индекс(вход, файлы, ожидаемый_sha256=хэш)
        with сам.assertRaises(ValueError):
            построить_пару({**пример(), 'журнал': '2026-07-02_11-14-15_MSK'})

    def test_все_строки_ссылки_и_соседи_индекса(сам):
        _, _, записи, файлы = сам._поколение()
        новый_вход = пример('альфа', '2026-10-10_11-00-00_MSK'); пара = построить_пару(новый_вход)
        вход, хэш = состав([записи[1], запись(пара, новый_вход), записи[0]])
        данные = {**файлы, **{ф['путь']: ф['байты'] for ф in пара['файлы']}}
        индекс = построить_индекс(вход, данные, ожидаемый_sha256=хэш)
        старый = '[перейти](../Журнал/2026-07-02_11-14-15_MSK/'
        средний = '[перейти](../Журнал/2026-10-10_11-00-00_MSK_%D0%B0%D0%BB%D1%8C%D1%84%D0%B0/'
        последний = '[перейти](../Журнал/2026-10-11_10-00-00_MSK_%D0%B1%D0%B5%D1%82%D0%B0/'
        запрос = '%D0%B7%D0%B0%D0%BF%D1%80%D0%BE%D1%81.md)'
        отчёт = '%D0%BE%D1%82%D1%87%D1%91%D1%82.md)'
        ожидаемые = [
            '| Историческая запись | ' + старый + запрос + ' | ' + старый + отчёт + ' | — | ' + средний + запрос + ' |',
            '| Этап альфа | ' + средний + запрос + ' | ' + средний + отчёт + ' | ' + старый + запрос + ' | ' + последний + запрос + ' |',
            '| Этап бета | ' + последний + запрос + ' | ' + последний + отчёт + ' | ' + средний + запрос + ' | — |']
        строки = [с for с in индекс['байты'].decode().splitlines() if с.startswith('| ')][2:]
        сам.assertEqual(строки, ожидаемые)
        сам.assertEqual(индекс['записей'], len(ожидаемые))

    def test_закрытый_состав_и_версия_записи(сам):
        _, _, записи, файлы = сам._поколение()
        for нарушение in ('версия', 'поле', 'режим', 'приёмка', 'пустой'):
            вход, _ = состав(copy.deepcopy(записи))
            if нарушение == 'версия': вход['записи'][0]['формат'] = 'fum.неизвестная.1'
            if нарушение == 'поле': вход['записи'][0]['лишнее'] = 1
            if нарушение == 'режим': вход['записи'][0]['файлы'][0]['режим'] = True
            if нарушение == 'приёмка': вход['записи'][0]['приёмка']['коммит'] = '6' * 7
            if нарушение == 'пустой': вход['записи'] = []
            вход, хэш = состав(вход['записи'])
            with сам.subTest(нарушение=нарушение), сам.assertRaises(ValueError):
                построить_индекс(вход, файлы, ожидаемый_sha256=хэш)

    def test_коллизия_нормализации_Unicode(сам):
        первый_вход = пример('ёлка'); второй_вход = пример(unicodedata.normalize('NFD', 'ёлка'))
        пары = [построить_пару(в) for в in (первый_вход, второй_вход)]
        вход, хэш = состав([запись(п, в) for п, в in zip(пары, (первый_вход, второй_вход))])
        файлы = {ф['путь']: ф['байты'] for п in пары for ф in п['файлы']}
        with сам.assertRaises(ValueError): построить_индекс(вход, файлы, ожидаемый_sha256=хэш)

    def test_один_снимок_не_имеет_двух_размеров(сам):
        вход = пример(); вторая = copy.deepcopy(вход['команды'][0])
        вторая['экземпляр'] = '8' * 64; вторая['снимок']['байты'] = 201
        вторая['позиция']['начало'] = 100; вторая['позиция']['конец'] = 200
        вход['команды'].append(вторая)
        with сам.assertRaises(ValueError): построить_пару(вход)



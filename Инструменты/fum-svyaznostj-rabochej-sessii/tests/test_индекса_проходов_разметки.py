@contextlib.contextmanager
def стенд(число=16, режим=0o644):
    """Раздельные H и носитель S исключают цикл глобальной свежести."""
    with история.стенд(режим) as (фикс, имя, файл, _):
        фикс.root = фикс.root.resolve()
        файл = фикс.root / имя
        for номер in range(число - 2):
            папка = f'2026-10-01_00-00-{номер:02d}_MSK_проверка-индекса-{номер:02d}'
            фикс.write(f'Журнал/{папка}/запрос.md', история.прежний.request_document(
                папка, previous=None, following=None, legacy=False,
                heading_title=f'Проверка индекса {номер:02d}'))
            фикс.write(f'Журнал/{папка}/отчёт.md', '# Отчёт\n\n[Запрос](запрос.md).\n')
        фикс.write('Индексы/вложенные/внешний.md', '# Внешняя разметка\n')
        фикс.write('.obsidian/graph.json', '{"наблюдение": 1}\n')
        фикс.write((Path('Журнал') / история.прежний.EARLY / 'материалы' / 'RAW.json').as_posix(), '{}\n')
        модуль = связность.модуль_свежести()
        итог = модуль.update_repository(фикс.root,
            now=datetime(2026, 10, 2, 0, 0, tzinfo=timezone.utc), use_git=False)
        if итог.errors:
            raise AssertionError(итог.errors)
        файл.chmod(режим)
        фикс.commit()
        журнал = связность.журнал()
        состав = журнал.состав_принятого_дерева(
            фикс.root, фикс.git('rev-parse', 'HEAD').stdout.strip())
        сырые = связность.контракт.канон(состав)
        фикс.write(журнал.ПУТЬ_СОСТАВА, сырые)
        фикс.write(журнал.ПУТЬ_ИНДЕКСА,
            журнал.построить_принятый_индекс(фикс.root, состав)['байты'])
        фикс.commit()
        выбор = {'коммит': фикс.git('rev-parse', 'HEAD').stdout.strip(),
            'путь': журнал.ПУТЬ_СОСТАВА, 'sha256': связность.контракт.хэш(сырые)}
        yield фикс, имя, файл, состав, выбор


def измерить(модуль, корень, состав, выбор, проход):
    """Обёртки делегируют ровно один исходный вызов и не меняют исключения."""
    исходный = Path.iterdir
    фаза = ['основной']
    счётчики = {имя: {'перечисления': 0, 'имена': 0}
        for имя in ('инвентарь', 'основной', 'поздний')}
    снимки = {}
    if проход == 'поздний':
        модуль.инвентарь_разметки(корень, состав=состав, снимки=снимки)

    def перечислить(каталог):
        if каталог != корень / 'Журнал':
            return исходный(каталог)
        счётчик = счётчики[фаза[0]]
        счётчик['перечисления'] += 1
        исходные = исходный(каталог)
        def выдать():
            for путь in исходные:
                счётчик['имена'] += 1
                yield путь
        return выдать()

    def пометить(действие, имя):
        def вызов(*аргументы, **параметры):
            прежняя = фаза[0]
            фаза[0] = имя
            try:
                return действие(*аргументы, **параметры)
            finally:
                фаза[0] = прежняя
        return вызов

    with mock.patch.object(Path, 'iterdir', перечислить), \
            mock.patch.object(модуль, 'инвентарь_разметки',
                пометить(модуль.инвентарь_разметки, 'инвентарь')), \
            mock.patch.object(модуль, 'сверить_снимки_разметки',
                пометить(модуль.сверить_снимки_разметки, 'поздний')):
        начало = time.perf_counter_ns()
        if проход == 'инвентарь':
            результат = модуль.инвентарь_разметки(корень, состав=состав, снимки=снимки)
        elif проход == 'поздний':
            результат = модуль.сверить_снимки_разметки(корень, снимки)
        else:
            результат = модуль.проверить_слой_разметки(
                корень, [], выбранный_состав=выбор)
        конец = time.perf_counter_ns()
    if проход == 'инвентарь':
        результат = sorted(результат)
    return {'начало_нс': начало, 'конец_нс': конец,
        'длительность_нс': конец - начало, 'фазы': счётчики}, результат


@contextlib.contextmanager
def наблюдать_индексы():
    журнал = связность.журнал()
    класс = журнал.ИндексПутей
    исходная_проверка = класс.проверить
    созданные, проверенные = [], []

    def создать(*аргументы, **параметры):
        индекс = класс(*аргументы, **параметры)
        созданные.append(индекс)
        return индекс

    def проверить(индекс):
        проверенные.append(индекс)
        return исходная_проверка(индекс)

    with mock.patch.object(журнал, 'ИндексПутей', создать), \
            mock.patch.object(класс, 'проверить', проверить):
        yield созданные, проверенные


class ИндексПроходовРазметки(unittest.TestCase):
    def test_реальные_перечисления_и_выданные_имена_16_32(сам):
        for число in (16, 32):
            with сам.subTest(число=число), стенд(число) as (фикс, _, _, состав, выбор):
                до = история.снимок_без_эффектов(фикс.root)
                соседей = len(list((фикс.root / 'Журнал').iterdir()))
                for проход in ('инвентарь', 'поздний', 'слой'):
                    with сам.subTest(проход=проход):
                        замер, результат = измерить(
                            связность, фикс.root, состав, выбор, проход)
                        if проход == 'слой':
                            сам.assertEqual([], результат[0])
                        активные = ('инвентарь', 'основной', 'поздний') \
                            if проход == 'слой' else (проход,)
                        for фаза, числа in замер['фазы'].items():
                            множитель = 2 if фаза in активные else 0
                            сам.assertEqual(
                                {'перечисления': множитель, 'имена': множитель * соседей},
                                числа, (число, проход, фаза, соседей))
                сам.assertEqual(до, история.снимок_без_эффектов(фикс.root))

    def test_внешние_пути_без_индекса_и_три_разных_наблюдения(сам):
        with стенд(2) as (фикс, _, _, _, выбор):
            журнал = связность.журнал()
            исходный = журнал.точный_путь
            наблюдения = []
            def точный(корень, имя, **параметры):
                наблюдения.append((имя, параметры.get('индекс')))
                return исходный(корень, имя, **параметры)
            with mock.patch.object(журнал, 'точный_путь', точный):
                ошибки, _ = связность.проверить_слой_разметки(
                    фикс.root, [], выбранный_состав=выбор)
            сам.assertEqual([], ошибки)
            индексы = {id(и): и for имя, и in наблюдения if имя.startswith('Журнал/')}
            сам.assertEqual(3, len(индексы))
            сам.assertTrue(all(и is not None and и.закрыт for и in индексы.values()))
            сам.assertTrue(all(и is None for имя, и in наблюдения if not имя.startswith('Журнал/')))
            сам.assertIn(('Индексы/вложенные/внешний.md', None), наблюдения)

    def test_дрейф_машинной_записи_и_прочего_файла_внутри_каждого_прохода(сам):
        for проход in ('инвентарь', 'основной', 'поздний'):
            for имя_дополнительного in ('RAW.json', 'другой.txt'):
                with сам.subTest(проход=проход, файл=имя_дополнительного), \
                        стенд(2) as (фикс, имя, файл, состав, выбор):
                    цель = файл.with_name(имя_дополнительного)
                    цель.write_text('Сохранённые данные\n')
                    снимки = {}
                    связность.инвентарь_разметки(фикс.root, состав=состав, снимки=снимки)
                    журнал = связность.журнал()
                    исходный = журнал.точный_путь
                    фаза = ['основной']
                    инвентарь = связность.инвентарь_разметки
                    def инвентаризация(*аргументы, **параметры):
                        фаза[0] = 'инвентарь'
                        try:
                            return инвентарь(*аргументы, **параметры)
                        finally:
                            фаза[0] = 'основной'
                    изменён = []
                    def точный(корень, путь, **параметры):
                        результат = исходный(корень, путь, **параметры)
                        if путь == имя and фаза[0] == проход and not изменён:
                            изменён.append(True)
                            цель.write_text('Изменённые данные\n')
                        return результат
                    if проход == 'поздний':
                        фаза[0] = проход
                    with mock.patch.object(журнал, 'точный_путь', точный), \
                            mock.patch.object(связность, 'инвентарь_разметки', инвентаризация):
                        with сам.assertRaisesRegex(ValueError, 'дрейф namespace'):
                            if проход == 'инвентарь':
                                связность.инвентарь_разметки(фикс.root, состав=состав)
                            elif проход == 'поздний':
                                связность.сверить_снимки_разметки(фикс.root, снимки)
                            else:
                                связность.проверить_слой_разметки(
                                    фикс.root, [], выбранный_состав=выбор)
                    сам.assertEqual([True], изменён)

    def test_поздний_инвентарь_обнаруживает_добавление_и_удаление(сам):
        for добавление in (True, False):
            with сам.subTest(добавление=добавление), стенд(2) as (фикс, _, файл, состав, _):
                снимки = {}
                связность.инвентарь_разметки(фикс.root, состав=состав, снимки=снимки)
                if добавление:
                    файл.with_name('новый.md').write_text('# Новый\n')
                else:
                    файл.unlink()
                with сам.assertRaisesRegex(ValueError, 'позднее изменение состава Markdown'):
                    связность.сверить_снимки_разметки(фикс.root, снимки)

    def test_изменение_графа_не_становится_входом_индекса(сам):
        with стенд(2) as (фикс, имя, _, состав, _):
            исходный = связность.прочитать_разметку
            def чтение(путь, **параметры):
                результат = исходный(путь, **параметры)
                if путь == фикс.root / имя:
                    (фикс.root / '.obsidian/graph.json').write_text('{"наблюдение": 2}\n')
                return результат
            with mock.patch.object(связность, 'прочитать_разметку', чтение):
                связность.инвентарь_разметки(фикс.root, состав=состав)

    def test_байты_разметки_между_проходами_отказывают(сам):
        with стенд(2) as (фикс, _, файл, состав, _):
            снимки = {}
            связность.инвентарь_разметки(фикс.root, состав=состав, снимки=снимки)
            файл.write_bytes(файл.read_bytes() + b'\n')
            with сам.assertRaisesRegex(ValueError, 'поздний дрейф прав или identity'):
                связность.сверить_снимки_разметки(фикс.root, снимки)

    def test_чужой_владелец_именно_материала_журнала_отказывает(сам):
        with стенд(2) as (фикс, _, файл, состав, _):
            прочитать = связность.прочитать_разметку
            владелец = os.getuid()
            вызвано = []

            def чтение(путь, **параметры):
                if путь == файл:
                    вызвано.append(путь)
                    with mock.patch.object(связность.os, 'getuid', return_value=владелец + 1):
                        return прочитать(путь, **параметры)
                return прочитать(путь, **параметры)

            with mock.patch.object(связность, 'прочитать_разметку', чтение):
                with сам.assertRaises(ValueError):
                    связность.инвентарь_разметки(фикс.root, состав=состав)
            сам.assertEqual([файл], вызвано)

    def test_полный_слой_сохраняет_историю_и_закрывает_три_индекса(сам):
        for режим in (0o600, 0o644):
            with сам.subTest(режим=режим), стенд(2, режим) as (фикс, _, _, _, выбор):
                до = история.снимок_без_эффектов(фикс.root)
                with наблюдать_индексы() as (созданные, проверенные):
                    ошибки, _ = связность.проверить_слой_разметки(
                        фикс.root, [], выбранный_состав=выбор)
                сам.assertEqual([], ошибки)
                сам.assertEqual(3, len(созданные))
                сам.assertEqual(3, len({id(и) for и in созданные}))
                сам.assertEqual(созданные, проверенные)
                сам.assertTrue(all(и.закрыт for и in созданные))
                сам.assertEqual(до, история.снимок_без_эффектов(фикс.root))

    def test_исходное_исключение_сохраняется_во_всех_фазах(сам):
        for номер, цель in enumerate(('инвентарь', 'основной', 'поздний'), 1):
            with сам.subTest(фаза=цель), стенд(2) as (фикс, имя, файл, _, выбор):
                журнал = связность.журнал()
                точный = журнал.точный_путь
                фаза = ['основной']
                вызвано = []
                ошибка = OSError('Первичный отказ: ' + цель)

                def пометить(действие, метка):
                    def вызов(*аргументы, **параметры):
                        прежняя = фаза[0]
                        фаза[0] = метка
                        try:
                            return действие(*аргументы, **параметры)
                        finally:
                            фаза[0] = прежняя
                    return вызов

                def адрес(корень, путь, **параметры):
                    результат = точный(корень, путь, **параметры)
                    if путь == имя and фаза[0] == цель:
                        вызвано.append(фаза[0])
                        файл.with_name('RAW.json').chmod(0o600)
                        raise ошибка
                    return результат

                with наблюдать_индексы() as (созданные, проверенные), \
                        mock.patch.object(журнал, 'точный_путь', адрес), \
                        mock.patch.object(связность, 'инвентарь_разметки',
                            пометить(связность.инвентарь_разметки, 'инвентарь')), \
                        mock.patch.object(связность, 'сверить_снимки_разметки',
                            пометить(связность.сверить_снимки_разметки, 'поздний')):
                    with сам.assertRaises(OSError) as исход:
                        связность.проверить_слой_разметки(
                            фикс.root, [], выбранный_состав=выбор)
                сам.assertIs(ошибка, исход.exception)
                сам.assertEqual([цель], вызвано)
                сам.assertEqual(номер, len(созданные))
                сам.assertEqual(созданные[:-1], проверенные)
                сам.assertTrue(all(и.закрыт for и in созданные))

    def test_коллизии_регистра_и_нормализации_не_скрываются_индексом(сам):
        """Модель коллизии не участвует в счётчиках настоящего перечисления."""
        for вид in ('case', 'NFC'):
            with сам.subTest(вид=вид), стенд(2) as (фикс, _, файл, состав, _):
                имя = (файл.name.upper() if вид == 'case'
                    else unicodedata.normalize('NFD', файл.name))
                алиас = файл.with_name(имя)
                сам.assertNotEqual(алиас, файл)
                ключ = связность.контракт.ключ_коллизии
                сам.assertEqual(ключ(алиас.name), ключ(файл.name))
                перечислить, лстат = Path.iterdir, Path.lstat

                def имена(каталог):
                    исходные = перечислить(каталог)
                    if каталог == файл.parent:
                        return iter([*исходные, алиас])
                    return исходные

                def метаданные(путь, *аргументы, **параметры):
                    return лстат(файл if путь == алиас else путь, *аргументы, **параметры)

                with mock.patch.object(Path, 'iterdir', имена), \
                        mock.patch.object(Path, 'lstat', метаданные):
                    with сам.assertRaisesRegex(ValueError, 'регистр или коллизия компонента'):
                        связность.инвентарь_разметки(фикс.root, состав=состав)



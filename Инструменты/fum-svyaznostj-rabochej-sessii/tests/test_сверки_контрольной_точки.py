def снимок(каталог):
    результат = {}
    for путь in [каталог, *sorted(каталог.rglob('*'))]:
        с = путь.lstat()
        результат[str(путь.relative_to(каталог))] = (
            с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink, с.st_size if путь.is_file() else None,
            с.st_mtime_ns, с.st_ctime_ns,
            os.readlink(путь) if путь.is_symlink() else хэш(путь.read_bytes()) if путь.is_file() else None)
    return результат



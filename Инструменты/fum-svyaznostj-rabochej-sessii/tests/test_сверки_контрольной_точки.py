def кли_в_процессе(ф, модуль):
    """Настоящая главная и её каналы; producer уже выполнился без подмен."""
    вывод = io.TextIOWrapper(io.BytesIO(), encoding='utf-8')
    ошибки = io.TextIOWrapper(io.BytesIO(), encoding='utf-8')
    аргументы = [ОТНОСИТЕЛЬНЫЙ, '--вход', str(ф.вход), '--sha256', хэш(ф.вход.read_bytes())]
    with mock.patch.object(sys, 'argv', аргументы), mock.patch.object(sys, 'stdout', вывод), \
         mock.patch.object(sys, 'stderr', ошибки):
        код = модуль.главная()
        вывод.flush(); ошибки.flush()
        return {'код': код, 'stdout': вывод.buffer.getvalue().decode(),
            'stderr': ошибки.buffer.getvalue().decode()}



def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(',', ':'))+'\n').encode()


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def загрузить():
    имя = 'читающая_сверка_STEP0245'
    if имя not in sys.modules:
        описание = importlib.util.spec_from_file_location(имя, КОРЕНЬ / ОТНОСИТЕЛЬНЫЙ)
        модуль = importlib.util.module_from_spec(описание)
        sys.modules[имя] = модуль
        try:
            описание.loader.exec_module(модуль)
        except BaseException:
            del sys.modules[имя]
            raise
    return sys.modules[имя]



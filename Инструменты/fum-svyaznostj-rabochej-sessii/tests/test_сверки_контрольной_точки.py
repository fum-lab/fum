def чистый_клон(ф):
    """Настоящий чистый клон консервативного набора scripts, без bootstrap."""
    источник = ф.каталог / 'исходники'; источник.mkdir()
    for тема in ('fum-svyaznostj-rabochej-sessii', 'fum-otchyotyi-o-zapuskakh-proverok',
                 'fum-struktura-papok-zaprosov', 'fum-proektnye-fajly', 'fum-indeks-proektnyikh-fajlov'):
        откуда = КОРЕНЬ / 'Инструменты' / тема / 'scripts'
        if откуда.exists():
            куда = источник / 'Инструменты' / тема / 'scripts'
            shutil.copytree(откуда, куда, ignore=shutil.ignore_patterns('__pycache__'))
    # Фактические импорты могут требовать ещё один канонический каталог scripts.
    for путь in (КОРЕНЬ / 'Инструменты').glob('*/scripts'):
        куда = источник / 'Инструменты' / путь.parent.name / 'scripts'
        if not куда.exists():
            shutil.copytree(путь, куда, ignore=shutil.ignore_patterns('__pycache__'))
    subprocess.run(['git', 'init', '-q', str(источник)], check=True)
    subprocess.run(['git', '-C', str(источник), 'add', '.'], check=True)
    subprocess.run(['git', '-C', str(источник), '-c', 'user.name=FUM', '-c',
        'user.email=fixture@example.invalid', 'commit', '-qm', 'Исполняемый контур'], check=True)
    клон = ф.каталог / 'чистый-клон'
    subprocess.run(['git', 'clone', '-q', '--no-local', str(источник), str(клон)], check=True)
    return клон



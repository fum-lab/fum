"""Парный профиль двух явных режимов на одной малой открытой фикстуре."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import statistics
import time
import unittest
from unittest import mock

from test_исторического_ручного_поручения import Фикстура, вход_до_акта, г, КОММИТ_КОДА, СВОЙ_КАТАЛОГ


def измерить_готовность(повторы):
    владелец = unittest.TestCase()
    try:
        ф = Фикстура(владелец)
        вход = вход_до_акта(ф)
        до = г.этап.коммит.охват.прочитать_статус(ф.ф.корень)[0]
        образцы = []
        for _ in range(повторы):
            with mock.patch.object(г.обычное,'прочитать_акт',side_effect=AssertionError('ACT не выбран')):
                начало = time.perf_counter_ns(); готовность = г.предпроверка(вход)
                длительность = time.perf_counter_ns()-начало
            assert готовность['не_разрешает_запись'] and готовность['внешние_действия']==[]
            образцы.append(длительность)
        assert до==г.этап.коммит.охват.прочитать_статус(ф.ф.корень)[0]
        assert not list(Path(вход['каталог_выходов']).iterdir())
        return {'образцы_нс':образцы,'медиана_нс':int(statistics.median(образцы)),
            'чтений_акта':0,'эффектов':0,'граница':'Только готовность заполненной пары без записи; подготовка фикстуры, публичный потребитель и очистка исключены.'}
    finally:
        владелец.doCleanups()


def измерить(повторы):
    исходники = {п.relative_to(СВОЙ_КАТАЛОГ).as_posix():hashlib.sha256(п.read_bytes()).hexdigest()
        for п in [Path(г.__file__),Path(г.историческое.__file__),Path(__file__),
            СВОЙ_КАТАЛОГ.joinpath('tests','test_исторического_ручного_поручения.py')]}
    владелец = unittest.TestCase()
    try:
        ф = Фикстура(владелец, шаблон=True)
        прежний = {к:з for к,з in ф.вход.items() if к not in {'снимок','журнал','исторические_записи'}}
        прежний['схема'] = 'fum.подготовка-дочернего-поручения.1'
        образцы = {'шаблонный':[], 'исторический':[]}
        планы = {}
        for _ in range(повторы):
            for режим in образцы:
                with mock.patch.object(г, 'гит', wraps=г.гит) as вызовы_гит, mock.patch.object(
                        г.этап.коммит.сообщения, 'прочитать_сообщения',
                        wraps=г.этап.коммит.сообщения.прочитать_сообщения) as вызовы_читателя:
                    начало = time.perf_counter_ns()
                    план = (г.построить_план(прежний) if режим=='шаблонный' else ф.план())
                    длительность = time.perf_counter_ns()-начало
                образцы[режим].append({'план_нс':длительность,
                    'вызовы_гит_генератора':вызовы_гит.call_count,
                    'вызовы_читателя_сообщений':вызовы_читателя.call_count,
                    'создаваемых_приватных_входов':len(план['установка']),
                    'подготовка':0, 'создание':0})
                планы[режим] = план
        старый = планы['шаблонный']['технические_входы']
        новый = планы['исторический']['технические_входы']
        assert set(старый['коммит']['разрешённые_цели']) | set(ф.сырые) == set(новый['коммит']['разрешённые_цели'])
        assert старый['будущие_записи'] == новый['будущие_записи']
        готовность = измерить_готовность(повторы)
        assert исходники == {п.relative_to(СВОЙ_КАТАЛОГ).as_posix():hashlib.sha256(п.read_bytes()).hexdigest()
            for п in [Path(г.__file__),Path(г.историческое.__file__),Path(__file__),
                СВОЙ_КАТАЛОГ.joinpath('tests','test_исторического_ручного_поручения.py')]}, 'Исходники изменились во время серии'
        return {'схема':'fum.профиль-исторического-поручения.1', 'коммит_зависимостей':КОММИТ_КОДА,
            'исходники':исходники, 'исходники_неизменны':True,
            'повторы':повторы, 'образцы':образцы, 'готовность_до_акта':готовность,
            'медианы_нс':{р:int(statistics.median(о['план_нс'] for о in з)) for р,з in образцы.items()},
            'проверенная_разница_T':len(ф.сырые), 'будущие_UUID_совпали':True,
            'граница':'Подготовка фикстуры, очистка, сериализация и публичный потребитель исключены. Счётчики именованных вызовов не равны физическому I/O.',
            'сравнимость':'Одна Git/native-фикстура и recipe. Исторический режим дополнительно сохраняет два прежних RAW; это измерение цены расширенного допуска, не ускорения равнозначной работы.',
            'решение_об_оптимизации':'Сохранить проверки и реализацию. Малый профиль не обосновывает сокращение preconditions; ускорение не заявляется.'}
    finally:
        владелец.doCleanups()


def главная():
    п = argparse.ArgumentParser(allow_abbrev=False)
    п.add_argument('--повторы',type=int,default=3)
    п.add_argument('--выход',required=True,type=Path)
    а = п.parse_args()
    if not 1 <= а.повторы <= 5:
        raise ValueError('нужно от одного до пяти повторов')
    выход = а.выход
    if not выход.is_absolute() or выход.exists() or выход.resolve()!=выход:
        raise ValueError('нужен новый физический абсолютный файл')
    for родитель in выход.parents:
        if (родитель/'.git').exists():
            raise ValueError('сырой профиль сохраняется вне Git')
    результат = измерить(а.повторы)
    выход.write_text(json.dumps(результат,ensure_ascii=False,sort_keys=True,indent=2)+'\n')
    выход.chmod(0o600)
    print(json.dumps({'выход_sha256':hashlib.sha256(выход.read_bytes()).hexdigest(),
        'медианы_нс':результат['медианы_нс'],'повторы':а.повторы},ensure_ascii=False))


if __name__ == '__main__':
    главная()

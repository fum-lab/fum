"""Живой служебный хвост не отменяет подлинную подготовку писателя."""
import json
from pathlib import Path
import unittest
from unittest.mock import patch

import test_переподготовка_ожиданий_узла as основа

писатель = основа.писатель


class СохранённаяМодельПисателя(unittest.TestCase):
    def setUp(сам):
        сам.ф = основа.ПереподготовкаОжиданий()
        сам.ф.setUp()
        сам.addCleanup(сам.ф.doCleanups)

    def дописать(сам, запись):
        with сам.ф.с.о.нативный.open('ab') as поток:
            поток.write((json.dumps(запись, ensure_ascii=False) + '\n').encode())

    def служебное(сам):
        сам.дописать({'type': 'event_msg', 'timestamp': '2026-10-02T00:00:01Z',
            'payload': {'type': 'agent_message', 'message': 'Подготовка завершена'}})

    def подготовить(сам):
        писатель.переподготовить(сам.ф.с.вход, сам.ф.ссылка)
        return json.loads(Path(сам.ф.новые['подготовка']).read_bytes())

    def снимок(сам):
        п = сам.ф.новые
        пути = [сам.ф.с.корень / п['история_модели'],
            *[Path(п[к]) for к in ('кэш_модели', 'подготовка', 'сообщение')]]
        return {str(путь): путь.read_bytes() for путь in пути}

    def сверить(сам, подготовка):
        return писатель.проверить_модель_подготовки(сам.ф.с.вход, сам.ф.новые, подготовка)

    def test_служебный_хвост_после_prepare_допускает_активацию_и_один_коммит(сам):
        исходная = писатель.коммит.подготовить
        сохранено = {}
        def подготовить(*аргументы, **ключи):
            итог = исходная(*аргументы, **ключи)
            сохранено.update(сам.снимок())
            сам.служебное()
            return итог
        with patch.object(писатель.коммит, 'подготовить', подготовить):
            писатель.переподготовить(сам.ф.с.вход, сам.ф.ссылка)
        сам.assertEqual(сохранено, сам.снимок())
        сам.ф.готовность()
        итог = писатель.зафиксировать(сам.ф.с.вход, [основа.исходные.обычная.база.ЗАПУСК])
        сам.assertEqual(итог, писатель.повтор(сам.ф.с.вход))
        сам.assertEqual('1', сам.ф.с.ф.гит('rev-list', '--count', сам.ф.с.база+'..HEAD').strip())

    def test_читающая_сверка_принимает_служебный_хвост_без_замены_RAW(сам):
        подготовка = сам.подготовить()
        до = сам.снимок()
        сам.служебное()
        сам.сверить(подготовка)
        сам.assertEqual(до, сам.снимок())

    def test_новое_наблюдение_той_же_модели_и_усилия_отвергается(сам):
        подготовка = сам.подготовить()
        сам.дописать({'type': 'turn_context', 'timestamp': '2026-10-03T00:00:00Z',
            'payload': {'cwd': str(сам.ф.с.корень), 'model': 'gpt-6.1-sol', 'effort': 'ultra'}})
        до = сам.снимок()
        with сам.assertRaises(ValueError): сам.сверить(подготовка)
        сам.assertEqual(до, сам.снимок())

    def test_повреждённый_и_незавершённый_хвост_отвергаются(сам):
        подготовка = сам.подготовить()
        нативный = сам.ф.с.о.нативный
        исходные = нативный.read_bytes()
        до = сам.снимок()
        for хвост in (b'{broken}\n', b'{"type":'):
            with сам.subTest(хвост=хвост):
                нативный.write_bytes(исходные + хвост)
                with сам.assertRaises(ValueError): сам.сверить(подготовка)
                сам.assertEqual(до, сам.снимок())

    def test_изменение_и_усечение_сохранённого_префикса_отвергаются(сам):
        подготовка = сам.подготовить()
        нативный = сам.ф.с.о.нативный
        исходные = нативный.read_bytes()
        до = сам.снимок()
        for байты in (b' ' + исходные[1:], исходные[:-1]):
            with сам.subTest(размер=len(байты)):
                нативный.write_bytes(байты)
                with сам.assertRaises(ValueError): сам.сверить(подготовка)
                сам.assertEqual(до, сам.снимок())

    def test_подготовленный_и_несогласованный_курсор_отвергаются(сам):
        подготовка = сам.подготовить()
        путь = Path(сам.ф.новые['кэш_модели'])
        исходные = путь.read_bytes()
        for вид in ('подготовлено', 'история'):
            курсор = json.loads(исходные)
            if вид == 'подготовлено': курсор['данные'][вид] = True
            else: курсор['данные'][вид]['число_наблюдений'] += 1
            курсор['sha256'] = писатель.коммит.модели.чтение._хэш(
                писатель.коммит.модели.чтение._байты(курсор['данные']))
            путь.write_bytes(писатель.коммит.модели.чтение._байты(курсор))
            до = сам.снимок()
            with сам.subTest(вид=вид), сам.assertRaises(ValueError): сам.сверить(подготовка)
            сам.assertEqual(до, сам.снимок())

    def test_дрейф_истории_или_курсора_во_время_наблюдения_отвергается(сам):
        подготовка = сам.подготовить()
        исходная = писатель.коммит.наблюдать_модель
        п = сам.ф.новые
        for путь in (сам.ф.с.корень / п['история_модели'], Path(п['кэш_модели'])):
            исходные = путь.read_bytes()
            def наблюдать(*аргументы, **ключи):
                итог = исходная(*аргументы, **ключи)
                путь.write_bytes(исходные + b'\n')
                return итог
            with сам.subTest(файл=путь.name), patch.object(писатель.коммит, 'наблюдать_модель', наблюдать):
                with сам.assertRaises(ValueError): сам.сверить(подготовка)
            сам.assertEqual(исходные + b'\n', путь.read_bytes())
            путь.write_bytes(исходные)

    def test_подготовка_сверяет_всё_наблюдение_число_и_сохранённый_хэш(сам):
        подготовка = сам.подготовить()
        ложная_модель = {**подготовка['модель'], 'усилие': 'low'}
        до = сам.снимок()
        for ключ, значение in (('модель', ложная_модель),
                ('наблюдений', подготовка['наблюдений'] + 1), ('история_sha256', '0' * 64)):
            with сам.subTest(поле=ключ), сам.assertRaisesRegex(ValueError, 'подготовка модели изменилась'):
                сам.сверить({**подготовка, ключ: значение})
            сам.assertEqual(до, сам.снимок())


if __name__ == '__main__':
    unittest.main()

    def test_точный_закрытый_отслеживаемый_материал_0600_принимается_без_изменения(сам):
        with стенд() as (фикс, имя, файл, состав):
            до = файл.read_bytes(), идентичность(файл)
            сам.assertEqual('100644', фикс.git('ls-files', '--stage', '--', имя).stdout.split()[0])
            сам.assertIn(имя, связность.инвентарь_разметки(фикс.root))
            сам.assertEqual(до, (файл.read_bytes(), идентичность(файл)))


@contextlib.contextmanager
def стенд(режим=0o600):
    with репозиторий() as фикс:
        обычный.НезависимыйОбычныйЖурнал().основа(фикс)
        имя = (Path('Журнал') / прежний.EARLY / 'материалы' / 'исторический.md').as_posix()
        файл = фикс.root / имя
        файл.parent.mkdir(exist_ok=True)
        файл.write_text('# Исторический материал\n\nСохранённые байты.\n')
        файл.chmod(режим)
        фикс.commit()
        журнал = связность.журнал()
        состав = журнал.состав_принятого_дерева(фикс.root, фикс.git('rev-parse', 'HEAD').stdout.strip())
        (фикс.root / журнал.ПУТЬ_СОСТАВА).parent.mkdir(exist_ok=True)
        (фикс.root / журнал.ПУТЬ_СОСТАВА).write_bytes(связность.контракт.канон(состав))
        (фикс.root / журнал.ПУТЬ_ИНДЕКСА).write_bytes(журнал.построить_принятый_индекс(фикс.root, состав)['байты'])
        фикс.commit()
        yield фикс, имя, файл, состав


def идентичность(файл):
    мета = файл.lstat()
    return (мета.st_dev, мета.st_ino, мета.st_mode, мета.st_uid,
        мета.st_nlink, мета.st_size, мета.st_mtime_ns, мета.st_ctime_ns)


@contextlib.contextmanager
def полный_стенд(режим):
    import test_независимой_контрольной_точки as сценарии
    class ИсторическийСоздатель(сценарии.РеальныйНезависимыйСоздатель):
        def обновить_свежесть(сам):
            if not hasattr(сам, 'исторический_файл'):
                сам.исторический_файл = сам.ф.запрос.parent / 'материалы/исторический.md'
                сам.исторический_файл.parent.mkdir(exist_ok=True)
                сам.исторический_файл.write_text('# Закрытый материал\n\nИсторические байты.\n')
                сам.исторический_файл.chmod(режим)
            super().обновить_свежесть()
    испытание = ИсторическийСоздатель()
    try:
        испытание.setUp()
        yield испытание
    finally:
        испытание.doCleanups()


def снимок_без_эффектов(корень):
    return {п.relative_to(корень).as_posix(): (п.read_bytes(), идентичность(п))
        for п in корень.rglob('*') if п.is_file()}



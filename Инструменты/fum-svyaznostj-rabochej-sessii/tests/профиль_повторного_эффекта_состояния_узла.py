class УчётЧтенияИсточников:
    """Байты настоящих файловых API, включая prefetch; I/O носителя неизвестен."""
    def __init__(сам, пути):
        assert 0 < len(пути) <= 2
        сам.личности = {(п.stat().st_dev,п.stat().st_ino):роль for п, роль in zip(пути,('координатор','владелец'))}
        сам.метрики = {'позиционных_байтов':0,'буферных_байтов':0,
            'байтов_чтения_в_буфер':0,'байтов_чтения_до_конца':0,'байтов_сырого_чтения':0}
        сам.по_источникам = {роль:dict(сам.метрики) for роль in сам.личности.values()}

    def исходник(сам, дескриптор):
        состояние = os.fstat(дескриптор)
        return (состояние.st_dev,состояние.st_ino) in сам.личности

    def учесть(сам, дескриптор, поле, число):
        состояние = os.fstat(дескриптор); роль = сам.личности.get((состояние.st_dev,состояние.st_ino))
        if роль is not None:
            сам.метрики[поле] += число; сам.по_источникам[роль][поле] += число

    def __enter__(сам):
        # Формула закреплена docstring самого исполняемого CPython, не угадана.
        assert 'max(min(blocksize, 8 MiB), DEFAULT_BUFFER_SIZE)' in io.open.__doc__
        сам.позиционное = os.pread; сам.буферное = os.fdopen
        def читать(дескриптор, число, смещение):
            данные = сам.позиционное(дескриптор,число,смещение)
            сам.учесть(дескриптор,'позиционных_байтов',len(данные))
            return данные
        def открыть(дескриптор, *аргументы, **параметры):
            поток = сам.буферное(дескриптор,*аргументы,**параметры)
            if not сам.исходник(дескриптор): return поток
            assert isinstance(поток,io.BufferedReader) and аргументы == ('rb',) and not параметры
            состояние = os.fstat(дескриптор)
            размер = max(min(состояние.st_blksize,8*1024*1024),io.DEFAULT_BUFFER_SIZE)
            сырой = поток.detach()
            return io.BufferedReader(СыройПотокПрофиля(сырой,сам),buffer_size=размер)
        os.pread = читать; os.fdopen = открыть
        return сам

    def __exit__(сам, *исход):
        os.pread = сам.позиционное; os.fdopen = сам.буферное


class СыройПотокПрофиля(io.RawIOBase):
    """Сохраняет FileIO.read/readall/readinto под прежним BufferedReader."""
    def __init__(сам, поток, учёт):
        сам.поток = поток; сам.учёт = учёт
    def readinto(сам, буфер):
        число = сам.поток.readinto(буфер)
        if число is not None:
            сам.учёт.учесть(сам.fileno(),'буферных_байтов',число)
            сам.учёт.учесть(сам.fileno(),'байтов_чтения_в_буфер',число)
        return число
    def read(сам, число=-1):
        данные = сам.поток.read(число)
        if данные is not None:
            сам.учёт.учесть(сам.fileno(),'буферных_байтов',len(данные))
            сам.учёт.учесть(сам.fileno(),'байтов_сырого_чтения',len(данные))
        return данные
    def readall(сам):
        данные = сам.поток.readall()
        if данные is not None:
            сам.учёт.учесть(сам.fileno(),'буферных_байтов',len(данные))
            сам.учёт.учесть(сам.fileno(),'байтов_чтения_до_конца',len(данные))
        return данные
    def readable(сам): return сам.поток.readable()
    def writable(сам): return сам.поток.writable()
    def seekable(сам): return сам.поток.seekable()
    def seek(сам, смещение, откуда=0): return сам.поток.seek(смещение,откуда)
    def tell(сам): return сам.поток.tell()
    def fileno(сам): return сам.поток.fileno()
    def isatty(сам): return сам.поток.isatty()
    def flush(сам): return сам.поток.flush()
    def close(сам):
        if not сам.closed:
            try: super().close()
            finally: сам.поток.close()
    def __getattr__(сам, имя): return getattr(сам.поток,имя)



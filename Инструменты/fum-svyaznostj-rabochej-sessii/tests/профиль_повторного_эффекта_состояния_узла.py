def сумма_файла(путь):
    сумма_потока=hashlib.sha256()
    with путь.open('rb') as поток:
        while блок:=поток.read(1024*1024): сумма_потока.update(блок)
    return сумма_потока.hexdigest()


def снимок_исходников():
    пути=(Path(__file__).resolve(),Path(фикстуры.__file__).resolve(),
        Path(запуск.__file__).resolve(),Path(фикстуры.базис.__file__).resolve())
    return {п.relative_to(КОРЕНЬ).as_posix():сумма_файла(п) for п in пути}



def _снимок_файлов_приёма(каталог):
    результат = {}
    for путь in [каталог,*каталог.rglob('*')]:
        состояние = путь.lstat(); запись = {'метаданные':запуск.отпечаток(состояние)}
        if stat.S_ISREG(состояние.st_mode): запись.update(тип='файл',sha256=сумма_файла(путь))
        elif stat.S_ISDIR(состояние.st_mode): запись.update(тип='каталог')
        elif stat.S_ISLNK(состояние.st_mode): запись.update(тип='symlink',цель=os.readlink(путь))
        else: raise AssertionError('Нетиповой узел профильной фикстуры')
        результат[путь.relative_to(каталог).as_posix()] = запись
    return результат



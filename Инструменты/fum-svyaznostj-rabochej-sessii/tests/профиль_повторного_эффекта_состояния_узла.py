def собрать_приём(каталог):
    начало = time.perf_counter_ns(); каталог.mkdir(mode=0o700)
    рабочее = каталог/'фикстура'; рабочее.mkdir(mode=0o700)
    пример = фикстуры.ПримерИсполняемогоПриёма(рабочее)
    обычные = фикстуры.ЕдиныйУчётНативногоПотока()
    for роль, исходный_порядок in (('координатор',4),('владелец',5)):
        with пример.пути[роль].open('ab') as поток:
            for номер in range(32768):
                запись = обычные.элемент(номер='профиль-B-'+роль+'-'+str(номер)+'-'+'x'*256)
                запись['ordinal'] = исходный_порядок+номер

def собрать(каталог):
    начало=time.perf_counter_ns(); каталог.mkdir(mode=0o700)
    отправка,получение,акт,якорь=фикстуры.НативнаяПараБазиса().пример(хост=True)
    обычные=фикстуры.ЕдиныйУчётНативногоПотока(); копии=фикстуры.КопииПервичныхРамок()
    источники={}; числа={КООРДИНАТОР:65536,ВЛАДЕЛЕЦ:4096}
    for задача,число in числа.items():
        роль='координатор' if задача==КООРДИНАТОР else 'владелец'
        путь=каталог/('координатор.jsonl' if задача==КООРДИНАТОР else 'владелец.jsonl')
        сумма_потока=hashlib.sha256(); позиция=0; граница=None; порядок=0
        with путь.open('xb') as поток:
            def строка(запись):
                nonlocal позиция,порядок
                запись['ordinal']=порядок; порядок+=1
                д=запись['payload']
                if 'thread_id' in д: д['thread_id']=задача
                if 'turn_id' in д: д['turn_id']=задача
                if 'internal_chat_message_metadata_passthrough' in д:
                    д['internal_chat_message_metadata_passthrough']['turn_id']=задача
                б=запуск.байты(запись); поток.write(б); сумма_потока.update(б); позиция+=len(б)
            строка(рождение(задача,каталог))
            if задача==КООРДИНАТОР: строка(копии.user())
            строка(обычные.вызов_инструмента())
            for номер in range(число):
                строка(обычные.элемент(номер='элемент-'+str(номер)+'-'+'x'*256))
                if номер==число//2: граница={'граница':позиция,'sha256':сумма_потока.hexdigest()}
            строка(обычные.исход_инструмента())
            if задача==КООРДИНАТОР:
                строка(копии.usercopy())
                начало_отправки=copy.deepcopy(отправка)
                начало_отправки['payload']['type']='item_started'
                начало_отправки['payload']['item']['status']='in_progress'
                строка(начало_отправки); строка(copy.deepcopy(отправка))
            else:
                строка(copy.deepcopy(получение))
                д=получение['payload']
                строка(копии.event({к:д[к] for к in ('id','name','namespace','output')}|{'type':'FunctionCallOutput'},
                    источник=задача))
        путь.chmod(0o400)
        источники[задача]={'роль':роль,'задача':задача,'путь':str(путь),
            'начало':граница,'конец':{'граница':позиция,'sha256':сумма_потока.hexdigest()}}
    вход={'источники':источники,'акт':акт,'якорь':якорь,'корень':str(каталог),
        'начальный_коммит':'a'*40,'рамок_всего':sum(числа.values())+12}
    путь=каталог/'вход.json'; путь.write_bytes(запуск.байты(вход)); путь.chmod(0o400)
    return путь,time.perf_counter_ns()-начало



"""Парный полный путь на одной открытой Git/native-фикстуре; кэш ОС не очищается."""
import argparse
import json
import statistics
import time
from pathlib import Path

from test_локальные_решения_сообщений import ПроверкаЛокальныхРешений, ЗАДАЧА, слой, штатная


def измерить(действие):
    начало = time.perf_counter_ns()
    try:
        итог = действие()
        результат = {'исход': 'прочитано', **итог}
    except слой.ОшибкаЛокальногоРешения as ошибка:
        результат = {'исход': 'отказ', 'профиль': getattr(ошибка, 'профиль', {})}
    return {**результат, 'весь_путь_наносекунды': time.perf_counter_ns() - начало}


def профиль(повторов, целей):
    фикстура = ПроверкаЛокальныхРешений()
    фикстура.setUp()
    try:
        for номер in range(3, целей + 2): фикстура.добавить('Сделай.\n', номер)
        снимок = фикстура.прочитать()
        номера = [н for н, э in enumerate(снимок['контекст']['экземпляры']) if э not in снимок['неизвестные']]
        for номер in номера:
            свежий = фикстура.прочитать()
            фикстура.сохранить(свежий, фикстура.предложение(свежий, номер))
        фикстура.коммит()
        def отпечаток():
            return {'HEAD': фикстура.гит('rev-parse', 'HEAD').decode().strip(),
                'дерево': фикстура.гит('rev-parse', 'HEAD^{tree}').decode().strip(),
                'native_sha256': штатная.хэш(фикстура.источник.read_bytes()),
                'локальная_история_sha256': штатная.хэш(фикстура.локальная.read_bytes()),
                'обычная_история_sha256': штатная.хэш(фикстура.обычная.read_bytes() if фикстура.обычная.exists() else b''),
                **слой.версии_читателей(), 'реализация_слоя_sha256': штатная.хэш(Path(слой.__file__).read_bytes()),
                'реализация_профиля_sha256': штатная.хэш(Path(__file__).read_bytes())}
        до = отпечаток()
        def без_слоя():
            чтение = слой.читатель._сеанс_чтения(фикстура.источник, ЗАДАЧА,
                корень_репозитория=фикстура.корень, без_записи=True)
            остаток = штатная.получить_остаток(фикстура.источник, ЗАДАЧА,
                корень_репозитория=фикстура.корень, без_записи=True, чтение=чтение)
            начало = time.perf_counter_ns()
            байтов = 0
            свидетельства = {}
            for номер in номера:
                запись = фикстура.предложение(остаток, номер)
                исходное = штатная.сверить_экземпляры(запись, {'сообщения': остаток['сообщения'],
                    'граница': остаток['контекст']['граница']})
                def читать(имя):
                    nonlocal байтов
                    байты = штатная.прочитать_файл(фикстура.корень / имя)
                    байтов += len(байты)
                    свидетельства[имя] = байты
                    return байты
                штатная.сверить_свидетельства(запись, исходное, читать)
            начало_свежей = time.perf_counter_ns()
            свежий = чтение()
            assert штатная.контекст_снимка(свежий) == остаток['контекст']
            assert фикстура.гит('rev-parse', 'HEAD').decode().strip() == до['HEAD']
            for имя, прежние in свидетельства.items():
                assert штатная.прочитать_файл(фикстура.корень / имя) == прежние
            return {'профиль': остаток['профиль'], 'построений_предложения': len(номера),
                'свежая_сверка': {'байтов': свежий['профиль']['прочитано_байтов'] + sum(map(len, свидетельства.values())),
                    'наносекунды': time.perf_counter_ns() - начало_свежей},
                'повторная_сверка_свидетельств': {'байтов': байтов, 'вызовов': len(номера) * 3,
                    'наносекунды': time.perf_counter_ns() - начало},
                'известных_целей': len(номера), 'неизвестных': len(снимок['неизвестные'])}
        def со_слоем():
            результат = фикстура.прочитать()
            assert len(результат['решения']) == целей
            assert {э['экземпляр'] for э in результат['решения']} == {снимок['контекст']['экземпляры'][н] for н in номера}
            assert all(э['переиспользуемо'] for э in результат['решения'])
            return {'профиль': результат['профиль'], 'построений_предложения': 0,
                'известных_целей': len(результат['решения']), 'неизвестных': len(результат['неизвестные'])}
        исходные = []; локальные = []; порядок = []
        for номер in range(повторов):
            пара = [('без_слоя', без_слоя, исходные), ('со_слоем', со_слоем, локальные)]
            if номер % 2: пара.reverse()
            порядок.append([э[0] for э in пара])
            for _, действие, выход in пара: выход.append(измерить(действие))
        после = отпечаток()
        assert до == после
        assert len(номера) == целей
        assert all(э['исход'] == 'прочитано' for э in исходные + локальные)
        # Новый unknown возвращает все цели на пересмотр; настоящий отказ дополнительно измеряется на усечении.
        фикстура.добавить('Новый неизвестный ввод.\n', целей + 2, неизвестное=True)
        начало = time.perf_counter_ns(); пересмотр = фикстура.прочитать()
        assert not any(э['переиспользуемо'] for э in пересмотр['решения'])
        пересмотр_профиля = {'исход': 'пересмотр', 'весь_путь_наносекунды': time.perf_counter_ns() - начало,
                            'профиль': пересмотр['профиль']}
        байты = фикстура.локальная.read_bytes(); фикстура.локальная.write_bytes(байты[:-1])
        отказы = [измерить(фикстура.прочитать) for _ in range(повторов)]
        assert all(э['исход'] == 'отказ' for э in отказы)
        return {'схема': 'fum.профиль-локальных-решений.1', 'повторов': повторов, 'известных_целей': целей,
            'фикстура_до': до, 'фикстура_после': после, 'порядок_пар': порядок,
            'без_локального_слоя': исходные, 'с_локальным_слоем': локальные, 'новый_контекст': пересмотр_профиля,
            'отказы': отказы, 'медианы_наносекунды': {
                'без_слоя': statistics.median(э['весь_путь_наносекунды'] for э in исходные),
                'со_слоем': statistics.median(э['весь_путь_наносекунды'] for э in локальные)},
            'граница': 'Измеряются чтение, построение восьми полей предложения и сверка свидетельств. '
                       'Человеческое мышление, качество решения, сеть и приёмка ROOT не измеряются. '
                       'Создание фикстуры, установка решений и запись профиля вне замеров; кэш ОС не очищается.'}
    finally:
        фикстура.doCleanups()


def главная():
    разбор = argparse.ArgumentParser(allow_abbrev=False)
    разбор.add_argument('--повторов', type=int, default=3)
    разбор.add_argument('--целей', type=int, default=4)
    разбор.add_argument('--выход', type=Path, required=True)
    параметры = разбор.parse_args()
    if not 1 <= параметры.повторов <= 100 or not 1 <= параметры.целей <= 100:
        разбор.error('Число повторов и целей должно быть от 1 до 100')
    результат = профиль(параметры.повторов, параметры.целей)
    параметры.выход.write_text(json.dumps(результат, ensure_ascii=False, sort_keys=True, indent=2) + '\n')
    print(json.dumps(результат['медианы_наносекунды'], ensure_ascii=False))


if __name__ == '__main__':
    главная()

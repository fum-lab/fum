"""Изолированный монотонный профиль читателя; Git-фикстура вне измеряемого участка."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import statistics

from test_обычного_поручения import ОбычноеПоручение


def измерить(повторы):
    случай = ОбычноеПоручение()
    случай.подготовить_фикстуру()
    try:
        исходники = [Path(__file__), Path(__file__).with_name('test_обычного_поручения.py'),
            *[Path(модуль.__file__) for модуль in [случай.модуль, случай.модуль.делегация,
                случай.модуль.история, случай.модуль.контракт, случай.модуль.постановка,
                случай.модуль.постановка.хранение, случай.модуль.охват,
                случай.модуль.охват.СВЯЗНОСТЬ]]]
        исходные_хэши = {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in исходники}
        профиль = {}
        вершина = случай.гит('rev-parse', 'HEAD')
        индекс = (случай.корень / '.git/index').read_bytes()
        прежний = None
        for _ in range(повторы):
            результат = случай.модуль.проверить(случай.параметры, случай.выбор, профиль=профиль)
            if прежний is not None:
                assert результат == прежний
            прежний = результат
        assert случай.гит('rev-parse', 'HEAD') == вершина
        assert (случай.корень / '.git/index').read_bytes() == индекс
        assert not (случай.корень / 'Журнал').exists()
        assert {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in исходники} == исходные_хэши
        return {'схема': 'fum.профиль-обычного-поручения.1', 'повторы': повторы,
            'единица': 'наносекунды', 'часы': 'perf_counter_ns', 'python': platform.python_version(),
            'среда': platform.platform(), 'создание-фикстуры-вне-замера': True,
            'записей-читателя': 0, 'общая-длительность-включает-стадии': True,
            'исходники': исходные_хэши, 'исходники-проверены-до-и-после': True,
            'стадии': {имя: {'замеры': замеры, 'медиана': statistics.median(замеры),
                'минимум': min(замеры), 'максимум': max(замеры)} for имя, замеры in профиль.items()}}
    finally:
        случай.doCleanups()


def главная():
    разбор = argparse.ArgumentParser()
    разбор.add_argument('--повторы', type=int, default=25)
    разбор.add_argument('--выход', type=Path, required=True)
    параметры = разбор.parse_args()
    if not 1 <= параметры.повторы <= 100:
        разбор.error('число повторов должно быть от 1 до 100')
    данные = измерить(параметры.повторы)
    параметры.выход.write_text(json.dumps(данные, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'повторы': данные['повторы'], 'медианы_нс': {
        имя: стадия['медиана'] for имя, стадия in данные['стадии'].items()}}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

"""Чистый расчёт конечного состава не зависит от позднего выбора полномочий."""
import copy
import importlib
from pathlib import Path
import sys
import unicodedata
import unittest
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))


class ЦелиСостояния(unittest.TestCase):
    def setUp(сам):
        сам.м = importlib.import_module('цели_ветки_состояния_узла')
        сам.вход = {
            'координатор': '01a07d3d-d376-7ad2-aafc-67e4c25a67eb',
            'sha256_постановки': 'a' * 64,
            'журнал': '2026-10-10_19-59-31_MSK_подготовить-генератор-состояния-узла',
            'первый_номер': 1, 'роль': 'исполнитель', 'число_проверок': 2,
            'цели': ['Состояние/узлы/fum-lab/fum/ожидаемое.json'],
            'прежние_записи': [],
        }

    def расчёт(сам, **поля):
        return сам.м.вывести_цели_состояния(**{**сам.вход, **поля})

    def test_точный_состав_без_побочных_эффектов(сам):
        до = copy.deepcopy(сам.вход)
        п = сам.расчёт()
        сам.assertEqual(до, сам.вход)
        сам.assertEqual(п, сам.расчёт())
        сам.assertEqual(7, len(п['цели']))
        сам.assertEqual(3, len(п['будущие_записи']))
        сам.assertEqual([1, 2], [э['порядок'] for э in п['проверки']])
        сам.assertEqual(3, п['связность']['порядок'])
        сам.assertEqual('Состояние/узлы/fum-lab/fum/ожидаемое.json', п['цели'][0])
        сам.assertNotIn('Журнал/README.md', п['цели'])
        сам.assertNotIn('Индексы/markdown-файлы-по-времени-редактирования.md', п['цели'])

    def test_исходная_постановка_журнал_номер_и_роль_различают_UUID(сам):
        исходные = {э['идентификатор'] for э in сам.расчёт()['проверки']}
        for поля in ({'sha256_постановки': 'b' * 64}, {'роль': 'корень'},
                {'первый_номер': 4}, {'журнал': сам.вход['журнал'].replace('19-59-31', '19-59-32')}):
            with сам.subTest(поля=поля):
                другие = {э['идентификатор'] for э in сам.расчёт(**поля)['проверки']}
                сам.assertFalse(исходные & другие)

    def test_полномочия_и_семантический_SHA_не_являются_входами(сам):
        for поле in ('полномочия_узла', 'sha256_семантики', 'акт', 'корень', 'ветка'):
            with сам.subTest(поле=поле):
                with сам.assertRaises(TypeError): сам.расчёт(**{поле: None})

    def test_явные_индексы_и_прежний_RAW_сохраняются(сам):
        старый = (Path('Журнал') / сам.вход['журнал'] / 'материалы/запуски-проверок' / '1_00000000-0000-0000-0000-000000000099.json').as_posix()
        п = сам.расчёт(первый_номер=2, прежние_записи=[старый],
            цели=[*сам.вход['цели'], 'Журнал/README.md', 'Индексы/markdown-файлы-по-времени-редактирования.md'])
        сам.assertIn(старый, п['цели'])
        сам.assertEqual([старый], п['существующие_записи'])
        сам.assertIn('Журнал/README.md', п['цели'])
        сам.assertEqual(2, п['проверки'][0]['порядок'])

    def test_цели_не_дают_произвольного_предметного_допуска(сам):
        абсолютный = (Path(Path('/').anchor) / 'ожидаемое.json').as_posix()
        for цель in ('../ожидаемое.json', абсолютный, 'Состояние//ожидаемое.json',
                'Состояние/./ожидаемое.json', 'Состояние/.скрытый.json', 'Состояние/ожидаемое.json/',
                'Журнал/чужой/запрос.md', 'Индексы/чужой.md'):
            with сам.subTest(цель=цель):
                with сам.assertRaises(ValueError): сам.расчёт(цели=[цель])
        for цели in ([], [*сам.вход['цели'], 'Код/чужой.py'], сам.вход['цели'] * 2,
                [*сам.вход['цели'], сам.вход['цели'][0].lower()]):
            with сам.subTest(цели=цели):
                with сам.assertRaises(ValueError): сам.расчёт(цели=цели)

    def test_плохая_идентичность_числа_и_дата_отказаны(сам):
        for поля in ({'координатор': 'не-UUID'}, {'sha256_постановки': 'A' * 64},
                {'роль': 'наблюдатель'}, {'первый_номер': True}, {'первый_номер': 0},
                {'число_проверок': -1}, {'число_проверок': False},
                {'журнал': сам.вход['журнал'].replace('2026-10-10', '2026-02-30')}):
            with сам.subTest(поля=поля):
                with сам.assertRaises(ValueError): сам.расчёт(**поля)

    def test_чужой_и_будущий_RAW_отказаны(сам):
        старый = (Path('Журнал') / сам.вход['журнал'] / 'материалы/запуски-проверок' / '1_00000000-0000-0000-0000-000000000099.json').as_posix()
        for записи in ([старый], [старый.replace(сам.вход['журнал'], 'чужой')],
                [старый.replace('1_00000000', '3_00000000')], [старый, старый], [старый.replace('.json', '.txt')]):
            with сам.subTest(записи=записи):
                with сам.assertRaises(ValueError): сам.расчёт(прежние_записи=записи)

    def test_литеральные_NFC_пути_и_будущие_UUID_не_поглощают_коллизии(сам):
        for цель in ('Состояние/*.json', 'Состояние/строка\n.json', 'Состояние/a:b.json',
                'Proyekcii/ожидаемое.json', unicodedata.normalize('NFD', 'Состояние/ещё.json')):
            with сам.subTest(цель=цель):
                with сам.assertRaises(ValueError): сам.расчёт(цели=[цель])
        with patch.object(сам.м.uuid, 'uuid5', return_value=сам.м.uuid.UUID('00000000-0000-0000-0000-000000000099')):
            with сам.assertRaisesRegex(ValueError, 'UUID'): сам.расчёт()


if __name__ == '__main__':
    unittest.main()

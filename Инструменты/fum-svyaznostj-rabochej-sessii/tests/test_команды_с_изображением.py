"""Нативный многочастный ввод сохраняет текст и связь со всем исходником."""
import copy
import json
from pathlib import Path
import unittest

import test_создание_коммита as база


class КомандыСИзображением(unittest.TestCase):
    def setUp(сам):
        сам.ф = база.СозданиеКоммита()
        сам.ф.setUp()
        сам.addCleanup(сам.ф.doCleanups)
        сам.исходный_запрос = сам.ф.запрос.read_text()

    def настроить(сам, части=None):
        if части is None:
            части = [
                {'type': 'input_text', 'text': база.КОМАНДА},
                {'type': 'input_text', 'text': '<image name=[Image #1] path="/private/снимок.png">'},
                {'type': 'input_image', 'image_url': 'data:image/png;base64,AAAA', 'detail': 'high'},
                {'type': 'input_text', 'text': '</image>'},
            ]
        сам.ф.события[-1]['payload']['content'] = copy.deepcopy(части)
        сам.ф.события[-1]['payload']['internal_chat_message_metadata_passthrough']['content_item_kinds'] = [
            'user.image' if ч['type'] == 'input_image' else 'user.text' for ч in части]
        сам.ф.записать_источник()
        снимок = база.прочитать_сообщения(сам.ф.источник, база.ЗАДАЧА,
            корень_репозитория=сам.ф.корень, без_записи=True)
        сам.ф.параметры['схема'] = 'fum.создание-коммита.6'
        сам.ф.параметры['источники'][0].update(
            экземпляры=[снимок['сообщения'][0]['экземпляр']],
            граница_снимка={'граница': снимок['граница'], 'sha256': снимок['sha256'],
                'неоднозначные_экземпляры': []})
        текст = '\n'.join(ч['text'] for ч in части if ч['type'] == 'input_text')
        сам.ф.запрос.write_text(сам.исходный_запрос.replace(
            '````text\n' + база.КОМАНДА + '\n````', '````text\n' + текст + '\n````'))
        return текст, снимок

    def test_реальное_создание_сохраняет_текст_и_сырой_отпечаток(сам):
        текст, снимок = сам.настроить()
        сам.ф.готовить()
        подготовка = json.loads(Path(сам.ф.параметры['подготовка']).read_bytes())
        сам.assertEqual('fum.подготовленный-коммит.8', подготовка['схема'])
        сам.assertEqual(снимок['сообщения'][0]['позиция'], подготовка['команды'][0]['позиция'])
        сам.assertEqual(текст, подготовка['команды'][0]['текст'])
        итог = сам.ф.создать()
        сырой = сам.ф.гит('cat-file', 'commit', итог['коммит'])
        сам.assertIn(текст, сырой)
        сам.assertNotIn('data:image/png;base64', сырой)
        сам.assertTrue(сырой.endswith('Codex-Thread-ID: ' + база.ЗАДАЧА + '\n'))
        сам.assertEqual(итог['коммит'], сам.ф.создать()['коммит'])

    def test_подмена_вложения_после_подготовки_не_создаёт_коммит(сам):
        сам.настроить()
        сам.ф.готовить()
        сам.ф.события[-1]['payload']['content'][2]['image_url'] = 'data:image/png;base64,AQAA'
        сам.ф.записать_источник()
        сам.ф.отказ_без_коммита(сам.ф.создать)
        сам.assertFalse(Path(сам.ф.параметры['квитанция']).exists())

    def test_прежний_формат_не_получает_молчаливого_расширения(сам):
        сам.настроить()
        сам.ф.параметры['схема'] = 'fum.создание-коммита.5'
        сам.ф.отказ_без_коммита(lambda: база.коммит.команды(сам.ф.параметры))

    def test_неизвестный_каркас_отказывает_до_подготовки(сам):
        сам.настроить()
        исходные = copy.deepcopy(сам.ф.события[-1]['payload']['content'])
        случаи = []
        for поле, значение in (('detail', 'unknown'), ('image_url', 'https://example.invalid/image.png'),
                              ('image_url', 'data:image/png;base64,AAA'), ('extra', 'скрытые данные')):
            части = copy.deepcopy(исходные)
            части[2][поле] = значение
            случаи.append(части)
        части = copy.deepcopy(исходные)
        части[3]['text'] = '</image> дополнительная команда'
        случаи.append(части)
        части = copy.deepcopy(исходные)
        части[1], части[2] = части[2], части[1]
        случаи.append(части)
        части = copy.deepcopy(исходные)
        части.append({'type': 'input_audio', 'text': 'неизвестная часть'})
        случаи.append(части)
        for части in случаи:
            with сам.subTest(типы=[ч['type'] for ч in части]):
                сам.настроить(части)
                до = сам.ф.источник.read_bytes()
                сам.ф.отказ_без_коммита(lambda: база.коммит.команды(сам.ф.параметры))
                сам.assertEqual(до, сам.ф.источник.read_bytes())
                сам.assertFalse(Path(сам.ф.параметры['сообщение']).exists())

    def test_потеря_текстовой_части_или_границы_отказывает(сам):
        текст, _ = сам.настроить()
        сам.ф.запрос.write_text(сам.ф.запрос.read_text().replace(текст, база.КОМАНДА))
        сам.ф.отказ_без_коммита(lambda: база.коммит.команды(сам.ф.параметры))
        сам.ф.параметры['источники'][0].pop('граница_снимка')
        сам.ф.отказ_без_коммита(lambda: база.коммит.команды(сам.ф.параметры))

    def test_одиночный_текст_совпадает_с_прежним_контрактом(сам):
        сам.настроить([{'type': 'input_text', 'text': база.КОМАНДА}])
        новые = база.коммит.команды(сам.ф.параметры)
        прежние = copy.deepcopy(сам.ф.параметры)
        прежние['схема'] = 'fum.создание-коммита.5'
        сам.assertEqual(новые, база.коммит.команды(прежние))
        сам.assertNotEqual(база.коммит.готовность.схема_обёртки(сам.ф.параметры),
            база.коммит.готовность.схема_обёртки(прежние))


if __name__ == '__main__':
    unittest.main()

"""Границы явной передачи определения, без предположений о памяти модели."""
import copy
import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from test_компактный_ответ_задачи import ЗАДАЧА, снимок_ответа, оболочка
from компактный_ответ_задачи import представить_ответ
from компактный_остаток import закодировать

КОРЕНЬ = Path(__file__).resolve().parents[3]
ПЕРЕДАЧА = "00000000-0000-0000-0000-000000000001"


class ПроверкаПояснений(unittest.TestCase):
    def test_ссылка_профиля_требует_целую_версию_в_обеих_формах(проверка):
        import пояснения_ответа as п
        данные = закодировать(оболочка(снимок_ответа()))
        полный = представить_ответ(данные, hashlib.sha256(данные).hexdigest(), ЗАДАЧА)
        первый = п.упаковать(полный, ПЕРЕДАЧА)
        подтверждение = п.подтвердить(первый, ПЕРЕДАЧА)
        сокращённый = п.упаковать(полный, ПЕРЕДАЧА, подтверждение)
        for версия in (True, 1.0, 999, None):
            with проверка.subTest(версия=версия, тип=type(версия).__name__):
                изменённый = copy.deepcopy(первый)
                изменённый["профиль"]["версия"] = версия
                with проверка.assertRaises(ValueError):
                    п.подтвердить(изменённый, ПЕРЕДАЧА)
                изменённый = copy.deepcopy(сокращённый)
                изменённый["профиль"]["версия"] = версия
                with проверка.assertRaises(ValueError):
                    п.восстановить(изменённый, первый["определение"], ПЕРЕДАЧА)

    def test_учёт_серии_не_складывает_повторно_вложенные_определения_и_подтверждения(проверка):
        from профиль_передачи_пояснений import итог_серии
        шаги = [
            {"запрос_байты": 10, "ответ_байты": 100, "определение_байты": 40, "подтверждение_байты": 0, "форма": "полная", "длительность_нс": 10},
            {"запрос_байты": 15, "ответ_байты": 60, "определение_байты": 0, "подтверждение_байты": 5, "форма": "ссылочная", "длительность_нс": 20},
            {"запрос_байты": 10, "ответ_байты": 100, "определение_байты": 40, "подтверждение_байты": 0, "форма": "полная", "длительность_нс": 30}]
        итог = итог_серии(шаги)
        проверка.assertEqual(итог["всего_байтов"], 295)
        проверка.assertEqual(итог["определения_внутри_ответов_байты"], 80)
        проверка.assertEqual(итог["подтверждения_внутри_запросов_байты"], 5)
        проверка.assertEqual(итог["полных_форм"], 2)
        проверка.assertEqual(итог["ссылочных_форм"], 1)
        проверка.assertEqual(итог["длительность_нс"], 60)

    def test_новая_версия_явная_и_бюджет_после_выбора_формы(проверка):
        данные = закодировать(оболочка(снимок_ответа()))
        with tempfile.TemporaryDirectory() as каталог:
            путь = Path(каталог) / "снимок ёж.json"
            путь.write_bytes(данные)
            команда = [sys.executable, "-B", str(КОРЕНЬ / "Инструменты/fum-svyaznostj-rabochej-sessii/scripts/показать-ответ-задачи.py"),
                "--снимок", str(путь), "--sha256", hashlib.sha256(данные).hexdigest(),
                "--задача", ЗАДАЧА, "--путь-в-результате"]
            прежний = subprocess.run(команда, capture_output=True, check=True).stdout
            новый = команда + ["--версия-передачи", "пояснения-1", "--передача-пояснений", ПЕРЕДАЧА]
            первый = subprocess.run(новый, capture_output=True)
            проверка.assertEqual(первый.returncode, 0, первый.stderr)
            import пояснения_ответа as п
            конверт = json.loads(первый.stdout)
            проверка.assertEqual(конверт["форма"], "полная")
            проверка.assertEqual(закодировать(п.восстановить(конверт)), прежний)
            подтверждение = п.подтвердить(конверт, ПЕРЕДАЧА)
            аргументы = ["--подтверждение-пояснений", json.dumps(подтверждение, ensure_ascii=False)]
            сжатый = subprocess.run(новый + аргументы, capture_output=True, check=True).stdout
            проверка.assertLess(len(сжатый), len(прежний))
            проверка.assertEqual(закодировать(п.восстановить(json.loads(сжатый), конверт["определение"], ПЕРЕДАЧА)), прежний)
            for профиль in ("прежний", "порождённый"):
                for дополнительные, ожидаемые in (([], первый.stdout), (аргументы, сжатый),
                        (["--подтверждение-пояснений", "повреждённый JSON"], первый.stdout)):
                    for бюджет in (len(ожидаемые), len(ожидаемые) - 1):
                        with проверка.subTest(профиль=профиль, бюджет=бюджет, подтверждение=bool(дополнительные)):
                            итог = subprocess.run(новый + дополнительные + ["--профиль", профиль,
                                "--максимум-байтов", str(бюджет)], capture_output=True)
                            проверка.assertEqual(итог.returncode, 0 if бюджет == len(ожидаемые) else 2, итог.stderr)
                            проверка.assertEqual(итог.stdout, ожидаемые if бюджет == len(ожидаемые) else b"")
            проверка.assertEqual(subprocess.run(команда, capture_output=True, check=True).stdout, прежний)
            проверка.assertEqual(путь.read_bytes(), данные)

    def test_подтверждение_не_следует_из_передачи_и_снимается_при_утрате(проверка):
        import пояснения_ответа as п
        данные = закодировать(оболочка(снимок_ответа()))
        полный = представить_ответ(данные, hashlib.sha256(данные).hexdigest(), ЗАДАЧА)
        первый = п.упаковать(полный, ПЕРЕДАЧА)
        определение = первый["определение"]
        проверка.assertIsNone(п.подготовить_подтверждение(определение, None, ПЕРЕДАЧА))
        подтверждение = п.подтвердить(первый, ПЕРЕДАЧА)
        проверка.assertEqual(п.подготовить_подтверждение(определение, подтверждение, ПЕРЕДАЧА), подтверждение)
        варианты = [(None, подтверждение, ПЕРЕДАЧА), ({}, подтверждение, ПЕРЕДАЧА),
            (определение, None, ПЕРЕДАЧА), (определение, подтверждение, "00000000-0000-0000-0000-000000000002")]
        for ключ, значение in (("версия", 999), ("sha256", "0" * 64), ("версия", True)):
            другой = copy.deepcopy(определение); другой[ключ] = значение
            варианты.append((другой, подтверждение, ПЕРЕДАЧА))
        for определение_сейчас, квитанция, передача in варианты:
            готовое = п.подготовить_подтверждение(определение_сейчас, квитанция, передача)
            проверка.assertIsNone(готовое)
            проверка.assertEqual(п.упаковать(полный, передача, готовое)["форма"], "полная")
        for ключ, значение in (("версия", 999), ("sha256", "0" * 64), ("передача", "чужая")):
            другое = dict(подтверждение); другое[ключ] = значение
            проверка.assertEqual(п.упаковать(полный, ПЕРЕДАЧА, другое)["форма"], "полная")
        сокращённый = п.упаковать(полный, ПЕРЕДАЧА, подтверждение)
        with проверка.assertRaisesRegex(ValueError, "полную форму"):
            п.восстановить(сокращённый, None, ПЕРЕДАЧА)
        проверка.assertEqual(п.упаковать(полный, ПЕРЕДАЧА, подтверждение, определение=None)["форма"], "полная")

    def test_выносятся_ровно_два_совпавших_поля_с_полной_обратимостью(проверка):
        import пояснения_ответа as п
        for пустой in (False, True):
            вход = снимок_ответа()
            if пустой:
                вход["turns"] = []
            данные = закодировать(оболочка(вход))
            полный = представить_ответ(данные, hashlib.sha256(данные).hexdigest(), ЗАДАЧА)
            полный["полный_снимок"]["путь"] = "/пример/ёж.json"
            исходные = закодировать(полный)
            первый = п.упаковать(полный, ПЕРЕДАЧА)
            подтверждение = п.подтвердить(первый, ПЕРЕДАЧА)
            сокращённый = п.упаковать(полный, ПЕРЕДАЧА, подтверждение)
            ожидаемый = copy.deepcopy(полный)
            del ожидаемый["полный_снимок"]["формат"]
            del ожидаемый["граница"]
            проверка.assertEqual(сокращённый["данные"], ожидаемый)
            проверка.assertEqual(закодировать(п.восстановить(сокращённый, первый["определение"], ПЕРЕДАЧА)), исходные)
            проверка.assertEqual(закодировать(полный), исходные)
            for поле in ("граница", "формат"):
                for значение in (None, "", "изменённая константа", "отсутствует"):
                    изменённый = copy.deepcopy(полный)
                    объект = изменённый if поле == "граница" else изменённый["полный_снимок"]
                    if значение == "отсутствует":
                        del объект[поле]
                    else:
                        объект[поле] = значение
                    выдача = п.упаковать(изменённый, ПЕРЕДАЧА, подтверждение)
                    проверка.assertEqual(выдача["форма"], "полная")
                    проверка.assertEqual(п.восстановить(выдача), изменённый)
            конфликт = copy.deepcopy(сокращённый)
            конфликт["данные"]["граница"] = "не перезаписывать"
            with проверка.assertRaises(ValueError):
                п.восстановить(конфликт, первый["определение"], ПЕРЕДАЧА)


if __name__ == "__main__":
    unittest.main()

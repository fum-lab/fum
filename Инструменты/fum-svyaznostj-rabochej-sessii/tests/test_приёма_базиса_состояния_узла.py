            сам.assertEqual(компиляция.call_count, 1)
            сам.assertFalse(маркер.exists(), 'контур исполнился после истечения срока в compile')
            сам.assertIsNotNone(ошибка)
            сам.assertIn('истёк бюджет начального чтения', ошибка)


        '----------''----------''----------''----------''----------'
        '----------''----------''----------''----------''--------'
        ' | '
        '----------''----------''----------''---------'
        ' |\n'
        '| [Индексы/markdown-файлы-по-времени-редактирования.md]'
        '(markdown-файлы-по-времени-редактирования.md)'
        ' | 2026-10-11 12:00:00 MSK'
        '          ''      '

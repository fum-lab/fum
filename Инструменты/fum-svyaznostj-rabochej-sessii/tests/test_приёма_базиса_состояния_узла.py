class ПолнотаСырыхОбъектов(unittest.TestCase):
    def setUp(сам):
        каталог = tempfile.TemporaryDirectory(prefix='fum-basis-raw-')
        сам.addCleanup(каталог.cleanup)
        сам.ф = ПримерБазиса(каталог.name)

    def сырой_гит(сам, *аргументы, данные=None):
        среда = базис.среда_гит()
        ответ = subprocess.run(['git', '--no-replace-objects', '--no-optional-locks',
            '-C', str(сам.ф.корень), *аргументы], input=данные,
            capture_output=True, env=среда, timeout=30)
        сам.assertEqual(ответ.returncode, 0, ответ.stderr.decode(errors='replace'))
        return ответ.stdout

    def удалить_объект(сам, идентификатор):
        # Здесь отдельная временная object database, без alternates и упаковки.
        путь = сам.ф.корень / '.git/objects' / идентификатор[:2] / идентификатор[2:]
        сам.assertTrue(путь.is_file())
        путь.unlink()

    def коммит_дерева(сам, дерево, родители, сообщение):
        аргументы = ['commit-tree', дерево]
        for родитель in родители:
            аргументы.extend(['-p', родитель])
        return сам.сырой_гит(*аргументы, '-m', сообщение).decode().strip()

    def добавить_первую_запись(сам, режим, идентификатор):
        ф = сам.ф
        снимки = {'X': ф.общий_предок, 'R': ф.исходное_состояние, 'K': ф.принятый_код, 'B': ф.принимаемый_базис}
        новые = {}
        добавка = режим.encode() + b' a.bin\0' + bytes.fromhex(идентификатор)
        for метка in ('X', 'R', 'K', 'B'):
            дерево = гит(ф.корень, 'rev-parse', снимки[метка] + '^{tree}')
            содержимое = добавка + сам.сырой_гит('cat-file', 'tree', дерево)
            новое_дерево = сам.сырой_гит('hash-object', '-t', 'tree', '--literally',
                '-w', '--stdin', данные=содержимое).decode().strip()
            родители = [снимки['X']] if метка == 'X' else [новые['X']] if метка in ('R', 'K') else [новые['K'], новые['R']]
            новые[метка] = сам.коммит_дерева(новое_дерево, родители, 'Сырой снимок ' + метка)
        ф.общий_предок = новые['X']
        ф.исходное_состояние = новые['R']
        ф.принятый_код = новые['K']
        ф.принимаемый_базис = новые['B']

    def test_нечитанный_неизменённый_файл_обязан_существовать(сам):
        ф = сам.ф
        до = ф.состав()
        сам.assertNotIn('общий.bin', {э['путь'] for э in до['входящий_состав']})
        идентификатор = гит(ф.корень, 'rev-parse', ф.общий_предок + ':общий.bin')
        сам.удалить_объект(идентификатор)
        with сам.assertRaises(ValueError):
            ф.состав()

    def test_сырые_байты_неизменённого_файла_сверяются_с_идентификатором(сам):
        import zlib
        ф = сам.ф
        ф.состав()
        идентификатор = гит(ф.корень, 'rev-parse', ф.общий_предок + ':общий.bin')
        путь = ф.корень / '.git/objects' / идентификатор[:2] / идентификатор[2:]
        данные = b'corrupted\x00blob\n'
        путь.chmod(0o600)
        путь.write_bytes(zlib.compress(b'blob ' + str(len(данные)).encode() + b'\0' + данные))
        with сам.assertRaisesRegex(ValueError, 'не соответствует сырым байтам'):
            ф.состав()

    def test_второй_родитель_исторического_слияния_не_пропускается(сам):
        ф = сам.ф
        дерево = гит(ф.корень, 'rev-parse', ф.общий_предок + '^{tree}')
        боковой = сам.коммит_дерева(дерево, [ф.общий_предок], 'Исторический второй родитель')
        новое_состояние = сам.коммит_дерева(гит(ф.корень, 'rev-parse', ф.исходное_состояние + '^{tree}'),
            [ф.исходное_состояние, боковой], 'Историческое слияние')
        ф.принимаемый_базис = сам.коммит_дерева(гит(ф.корень, 'rev-parse', ф.принимаемый_базис + '^{tree}'),
            [ф.принятый_код, новое_состояние], 'Базис исторического слияния')
        ф.исходное_состояние = новое_состояние
        ф.состав()
        сам.удалить_объект(боковой)
        with сам.assertRaises(ValueError):
            ф.состав()

    def test_пустое_вложенное_дерево_не_скрывается_листовым_перечнем(сам):
        пустое = сам.сырой_гит('hash-object', '-t', 'tree', '-w', '--stdin', данные=b'').decode().strip()
        сам.добавить_первую_запись('40000', пустое)
        with сам.assertRaises(ValueError):
            сам.ф.состав()

    def test_тип_неизменённого_листа_проверяется(сам):
        сам.добавить_первую_запись('100644', сам.ф.общий_предок)
        with сам.assertRaises(ValueError):
            сам.ф.состав()

    def test_сырой_режим_дерева_должен_быть_каноническим(сам):
        файл = сам.сырой_гит('hash-object', '-t', 'blob', '-w', '--stdin', данные=b'leaf\n').decode().strip()
        дерево = сам.сырой_гит('hash-object', '-t', 'tree', '-w', '--stdin',
            данные=b'100644 leaf\0' + bytes.fromhex(файл)).decode().strip()
        сам.добавить_первую_запись('040000', дерево)
        with сам.assertRaisesRegex(ValueError, 'режим'):
            сам.ф.состав()

    def test_старая_неизменённая_ссылка_остаётся_непрозрачной(сам):
        ссылка = сам.сырой_гит('hash-object', '-t', 'blob', '-w', '--stdin',
            данные=b'../../outside/target').decode().strip()
        сам.добавить_первую_запись('120000', ссылка)
        состав = сам.ф.состав()
        сам.assertNotIn('a.bin', {э['путь'] for э in состав['входящий_состав']})



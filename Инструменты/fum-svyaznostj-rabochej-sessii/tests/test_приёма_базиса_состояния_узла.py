class СвежестьДокумента(unittest.TestCase):
    def документ(сам, содержание, *, дата='2026-10-11 19:14:43 MSK', основание=None):
        содержание = содержание if содержание.endswith('\n') else содержание + '\n'
        сумма = hashlib.sha256((основание or содержание).encode()).hexdigest()
        return (содержание + '\n<!-- FUM-MD-RECENCY:BEGIN -->\n'
            + '<!-- last-content-edit: ' + дата + ' -->\n'
            + '<!-- content-sha256: sha256:' + сумма + ' -->\n'
            + '<!-- FUM-MD-RECENCY:END -->\n').encode()

    def отчёт(сам, тело='Результат первого запуска', состояние=None):
        начало = состояние or 'состояние=открыт; каталог=материалы/запуски-проверок'
        return ('# Отчёт\n\n<!-- FUM-CHECK-RUNS:BEGIN ' + начало + ' -->\n'
            + тело + '\n<!-- FUM-CHECK-RUNS:END -->\n')

    def test_содержательный_и_сырой_хэши_различаются(сам):
        данные = сам.документ('# Основа\n')
        запись = базис.свежесть_документа('Основа.md', данные)
        сам.assertEqual(запись['содержание'], '# Основа\n')
        сам.assertEqual(запись['дата'], '2026-10-11 19:14:43 MSK')
        сам.assertEqual(запись['сырой_sha256'], hashlib.sha256(данные).hexdigest())
        сам.assertEqual(запись['содержательный_sha256'], hashlib.sha256(b'# '+ 'Основа\n'.encode()).hexdigest())

    def test_содержательная_подмена_при_прежней_метке_отклоняется(сам):
        данные = сам.документ('# Основа\n').replace('Основа'.encode(), 'Подмена'.encode())
        with сам.assertRaisesRegex(ValueError, 'свежест'):
            базис.свежесть_документа('Основа.md', данные)

    def test_лишний_перевод_строки_содержателен(сам):
        данные = сам.документ('# Основа\n').replace(b'\n\n<!-- FUM-MD', b'\n\n\n<!-- FUM-MD')
        with сам.assertRaisesRegex(ValueError, 'свежест'):
            базис.свежесть_документа('Основа.md', данные)

    def test_универсальные_переводы_строк_не_меняют_содержательный_хэш(сам):
        исходные = сам.документ('# Основа\n')
        запись = базис.свежесть_документа('Основа.md', исходные.replace(b'\n', b'\r\n'))
        сам.assertEqual(запись['содержание'], '# Основа\n')
        сам.assertNotEqual(запись['сырой_sha256'], hashlib.sha256(исходные).hexdigest())

    def test_ограждённая_цитата_метки_остаётся_содержанием(сам):
        тело = '# Основа\n\n````text\n<!-- FUM-MD-RECENCY:BEGIN -->\n```\n````\n'
        сам.assertEqual(базис.свежесть_документа('Основа.md', сам.документ(тело))['содержание'], тело)

    def test_незакрытая_ограда_скрывает_терминальную_метку(сам):
        with сам.assertRaisesRegex(ValueError, 'оград'):
            базис.свежесть_документа('Основа.md', сам.документ('# Основа\n\n```text\nЦитата\n'))

    def test_тильдовая_ограда_сохраняет_цитату_с_обратными_апострофами(сам):
        тело = '# Основа\n\n   ' + chr(126) * 4 + ' text\n```\n   ' + chr(126) * 4 + '\t\n'
        сам.assertEqual(базис.свежесть_документа('Основа.md', сам.документ(тело))['содержание'], тело)


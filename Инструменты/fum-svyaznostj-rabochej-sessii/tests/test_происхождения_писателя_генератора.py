def канонические_правила(источник, цель, свежесть):
    """Точные нормы и Git-источник; новые основания — открытые ресурсы фикстуры."""
    м = json.loads((источник/'Правила/агентов/инвентарь-правил.json').read_bytes())
    for правило in м['правила']:
        if not правило['источники']:
            правило['новое_основание'] = 'Основания/'+правило['идентификатор']+'.md'
    пути = {'AGENTS.md', 'Правила/агентов/инвентарь-правил.json',
        *[т['путь'] for т in м['темы']], *м['служебные_пути_изменения_правил'],
        *[п['новое_основание'] for п in м['правила'] if not п['источники']]}
    пути.update(м['продолжение_задачи']['остаток_сообщений'][к] for к in ('сценарий',))
    пути.add(м['продолжение_задачи']['сценарий'])
    for имя in ('дочерняя_передача', 'дочерний_приём'):
        пути.update(з for з in м[имя].values() if isinstance(з,str) and з.startswith('Инструменты/'))
    for имя in пути:
        ф = цель/имя; ф.parent.mkdir(parents=True,exist_ok=True)
        if имя.startswith('Основания/'):
            # Валидатор проверяет существование новых оснований, не их
            # содержимое. Открытая фикстура не выдаёт реальные чужие сеансы
            # за историю собственного writer и не меняет их навигацию.
            тело = '# Открытое основание фикстуры правил\n'
            ф.write_text(свежесть.attach_recency_block(тело,'2026-09-15 23:00:00 MSK',
                свежесть.content_digest(свежесть.canonical_content(тело))))
        else: shutil.copyfile(источник/имя,ф)
    (цель/'Правила/агентов/инвентарь-правил.json').write_bytes(примеры.примеры.байты(м))
    # Не создаём новую историю вместо указанного происхождения: переносим
    # точные три Git-объекта исходного канона без refs и прочих деревьев.
    коммит = м['исходный_снимок']['commit']
    сырые = subprocess.check_output(['git','-C',str(источник),'cat-file','commit',коммит])
    дерево = сырые.splitlines()[0].decode().removeprefix('tree ')
    for вид,oid in (('commit',коммит),('tree',дерево),('blob',м['исходный_снимок']['blob'])):
        б = subprocess.check_output(['git','-C',str(источник),'cat-file',вид,oid])
        фактический = subprocess.check_output(['git','-C',str(цель),'hash-object','-w','-t',вид,'--stdin'],input=б).decode().strip()
        if фактический!=oid: raise ValueError('изменился Git-объект исходного канона фикстуры')
    subprocess.run(['git','-C',str(цель),'add','--',*sorted(пути)],check=True)
    subprocess.run(['git','-C',str(цель),'commit','-qm','Канонические правила и открытые адреса оснований фикстуры'],check=True)


class ПроисхождениеПисателя(unittest.TestCase):
    def setUp(сам):
        подмена = mock.patch.object(примеры.примеры.база,'ЗАДАЧА',ROOT)
        подмена.start(); сам.addCleanup(подмена.stop)
        сам.п = примеры.ПодготовкаПоручения('test_предпросмотр_без_записи_и_обычная_подготовка')
        сам.п.setUp(); сам.addCleanup(сам.п.doCleanups)
        сам.м = сам.п.м; сам.ф = сам.п.ф; сам.вход = сам.п.вход
        канонические_правила(сам.м.ИНСТРУМЕНТЫ.parent,сам.ф.корень,сам.м.этап.свежесть)
        сам.ф.ф.гит('branch','-m','fuma')
        исторический = str(сам.ф.приватный/'первоначальный-checkout')
        сам.ф.ф.события[0]['payload']['cwd'] = исторический
        сам.ф.ф.события[1]['payload']['cwd'] = исторический
        сам.ф.ф.события.append({'type':'turn_context','timestamp':'2026-10-04T16:00:00Z',
            'payload':{'cwd':str(сам.ф.корень),'model':'gpt-6.1-sol','effort':'ultra'}})
        сам.обновить_источник()

    def обновить_источник(сам):
        сам.ф.ф.записать_источник()
        с = сам.вход['источники'][0]
        сам.номер_источника = getattr(сам,'номер_источника',0)+1
        с['кэш'] = str(сам.ф.приватный/('кэш-переноса-'+str(сам.номер_источника)+'.json'))
        снимок = сам.м.этап.коммит.сообщения.прочитать_сообщения(сам.ф.ф.источник,ROOT,
            корень_репозитория=сам.ф.корень,кэш=Path(с['кэш']))
        с.update(экземпляры=[э['экземпляр'] for э in снимок['сообщения'] if э['происхождение']=='человек'],
            граница_снимка={'граница':снимок['граница'],'sha256':снимок['sha256'],
                'неоднозначные_экземпляры':[э['экземпляр'] for э in снимок['сообщения'] if э['происхождение']!='человек']})

    def test_перенос_ROOT_проходит_план_и_подготовку_без_подмены_native(сам):
        сырые = сам.ф.ф.источник.read_bytes(); до = сам.ф.снимок()
        план = сам.м.построить_план(сам.вход)
        сам.assertEqual(до,сам.ф.снимок()); сам.assertEqual([],list(сам.п.выходы.iterdir()))
        сам.assertIn('gpt-6-astra',план['технические_входы']['наблюдённое_имя_автора'])
        файл = сам.п.выходы/'план.json'; файл.write_bytes(сам.м.байты(план)); файл.chmod(0o400)
        сам.м.применить(сам.вход,файл,сам.м.хэш(файл.read_bytes()))
        м = сам.м.этап; параметры = план['технические_входы']['коммит']
        stem = Path(параметры['запрос']).parent.name
        м.каркас.start_session(сам.ф.корень,stem,stem.split('_MSK_',1)[1],
            параметры['заголовок'],ROOT,[э['текст'] for э in м.корневые_команды(параметры)])
        (сам.ф.корень/параметры['история_модели']).parent.mkdir(parents=True,exist_ok=True)
        м.коммит.подготовить(параметры)
        подготовка = json.loads(Path(параметры['подготовка']).read_bytes())
        сам.assertIn('gpt-6.1-sol',json.dumps(подготовка,ensure_ascii=False))
        сам.assertEqual(сырые,сам.ф.ф.источник.read_bytes())

    def test_перенос_ROOT_проходит_вторую_корневую_фазу(сам):
        сам.п.подготовить_акт()
        сам.assertIsNotNone(сам.м.построить_план(сам.вход)['нативная_привязка'])

    def test_перенос_ROOT_состояния_ограничен_новой_фазой_полномочий(сам):
        начало,контекст,_ = сам.м.обычное.постановка.прочитать_начало_источника(сам.вход['источник_модели'])
        исходные = сам.ф.ф.источник.read_bytes(); до = сам.ф.снимок()
        в = copy.deepcopy(сам.вход); р = copy.deepcopy(сам.п.решение)
        в.update(схема='fum.подготовка-дочернего-поручения.6',фаза='полномочия')
        р['схема'] = 'fum.смысл-дочернего-поручения.4'
        основание = сам.м.происхождение.проверить(в,р,{'ref':'refs/heads/fuma'},начало,контекст,сам.ф.корень)
        сам.assertEqual('FUM-ПРАВИЛО-000121',основание['правило'])
        for схема,семантика,фаза,ref in (
            ('fum.подготовка-дочернего-поручения.1',р['схема'],'полномочия','refs/heads/fuma'),
            (в['схема'],'fum.смысл-дочернего-поручения.1','полномочия','refs/heads/fuma'),
            (в['схема'],р['схема'],'входы','refs/heads/fuma'),
            (в['схема'],р['схема'],'полномочия','refs/heads/codex/иной')):
            with сам.subTest(схема=схема,семантика=семантика,фаза=фаза,ref=ref):
                неверный = copy.deepcopy(в); решение = copy.deepcopy(р)
                неверный.update(схема=схема,фаза=фаза); решение['схема'] = семантика
                with сам.assertRaises(ValueError):
                    сам.м.происхождение.проверить(неверный,решение,{'ref':ref},начало,контекст,сам.ф.корень)
        чужой = '00000000-0000-0000-0000-000000000099'
        неверный = copy.deepcopy(в); решение = copy.deepcopy(р); native = copy.deepcopy(начало)
        неверный['писатель'] = решение['координатор'] = native['id'] = чужой
        with сам.assertRaisesRegex(ValueError,'исторический cwd не разрешает перенос этого писателя'):
            сам.м.происхождение.проверить(неверный,решение,{'ref':'refs/heads/fuma'},native,контекст,сам.ф.корень)
        сам.assertEqual(исходные,сам.ф.ф.источник.read_bytes())
        сам.assertEqual(до,сам.ф.снимок()); сам.assertEqual([],list(сам.п.выходы.iterdir()))


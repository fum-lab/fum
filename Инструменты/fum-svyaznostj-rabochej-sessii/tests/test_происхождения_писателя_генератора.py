    def test_неизвестный_или_повреждённый_допуск_закрывается(сам):
        инвентарь = сам.ф.корень/'Правила/агентов/инвентарь-правил.json'
        сырые = инвентарь.read_bytes(); данные = json.loads(сырые)
        правило = next(п for п in данные['правила'] if п['идентификатор']=='FUM-ПРАВИЛО-000121')
        for статус in ('история','контекст'):
            правило['статус'] = статус; инвентарь.write_bytes(сам.м.байты(данные))
            with сам.subTest(статус=статус),сам.assertRaises(ValueError): сам.м.построить_план(сам.вход)

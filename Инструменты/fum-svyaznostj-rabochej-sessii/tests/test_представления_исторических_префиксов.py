class ПолныеРазборыОперации(unittest.TestCase):
    стенд = исторические.ИсторическоеНачало.стенд
    план = исторические.ИсторическоеНачало.план
    применить = исторические.ИсторическоеНачало.применить

    def test_каждый_исходный_префикс_разбирается_один_раз_за_применение(сам):
        _, _, пример, состав, вход, сохранено = сам.стенд()
        план, файл = сам.план(пример, состав, вход, сохранено)
        контексты = [план['координация']['контекст'],
            план['историческое_основание']['контекст']]
        границы = {(к['граница'], к['sha256']) for к in контексты}
        читатель = историческое.поздний.основание.читатель
        исходный = читатель._прочитать_поток
        наблюдения = []

        def прочитать(поток, задача, прежний, **параметры):
            индекс, профиль = исходный(поток, задача, прежний, **параметры)
            ключ = (индекс['граница'], индекс['sha256'])
            if задача == план['свидетельство']['координатор'] and ключ in границы:
                наблюдения.append((ключ, профиль.copy()))
            return индекс, профиль

        with mock.patch.object(читатель, '_прочитать_поток', side_effect=прочитать), \
                mock.patch.object(историческое, '_построить_план',
                    wraps=историческое._построить_план) as построения:
            сам.применить(пример, состав, вход, сохранено, файл)
        сам.assertEqual(построения.call_count, 5)
        полные = [ключ for ключ, профиль in наблюдения if профиль['разобрано_строк']]
        сам.assertCountEqual(полные, границы,
            f'Повторные полные разборы вместо сверок сырых байтов: {полные!r}')
        сам.assertGreaterEqual(len(наблюдения), 35)
        for ключ, профиль in наблюдения:
            сам.assertEqual(профиль['прочитано_байтов'], ключ[0])
        наблюдения.clear()
        with mock.patch.object(читатель, '_прочитать_поток', side_effect=прочитать):
            повтор = сам.применить(пример, состав, вход, сохранено, файл)
        сам.assertTrue(повтор['повтор'])
        сам.assertCountEqual([ключ for ключ, профиль in наблюдения
            if профиль['разобрано_строк']], границы)


class ИзоляцияПредставлений(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory(prefix='FUM-представления-')
        сам.addCleanup(сам.временный.cleanup)
        сам.папка = Path(сам.временный.name).resolve()
        сам.путь = сам.папка / 'исходник.jsonl'
        сам.задача = '00000000-0000-4000-8000-000000000001'
        записи = [{'type':'session_meta','payload':{'id':сам.задача}},
            {'type':'response_item','payload':{'type':'message','role':'user',
                'content':[{'type':'input_text','text':'old'}]}}]
        сам.сырые = b''.join((json.dumps(з,ensure_ascii=False)+'\n').encode() for з in записи)
        сам.путь.write_bytes(сам.сырые); сам.путь.chmod(0o600)
        with сам.путь.open('rb') as поток:
            индекс,_ = основание.читатель._прочитать_поток(
                поток,сам.задача,None,предел=len(сам.сырые))
        сам.контекст = основание.обработка.контекст_снимка(индекс)

    def прочитать(сам, область, *, путь=None, задача=None, контекст=None):
        путь = путь or сам.путь
        with путь.open('rb') as поток:
            return основание._прочитать_в_операции(поток,путь,задача or сам.задача,
                контекст or сам.контекст,область)

    def test_копия_сверяет_все_байты_и_не_получает_закрытый_индекс(сам):
        копия=сам.папка/'копия.jsonl'; копия.write_bytes(сам.сырые); копия.chmod(0o600)
        with основание._ПредставленияПрефиксов() as область:
            первый,профиль=сам.прочитать(область)
            ожидаемый=copy.deepcopy(первый)
            первый['сообщения'].clear(); первый['транспорт'].clear()
            второй,повтор=сам.прочитать(область,путь=копия)
        сам.assertEqual(второй,ожидаемый)
        сам.assertGreater(профиль['разобрано_строк'],0)
        сам.assertEqual(повтор['разобрано_строк'],0)
        сам.assertEqual(повтор['прочитано_байтов'],len(сам.сырые))

    def test_новая_операция_снова_разбирает_исходные_строки(сам):
        for _ in range(2):
            with основание._ПредставленияПрефиксов() as область:
                _,профиль=сам.прочитать(область)
                сам.assertGreater(профиль['разобрано_строк'],0)
        with сам.assertRaises(ValueError): сам.прочитать(область)
        with сам.assertRaises(ValueError):
            with область: pass
        with сам.assertRaises(ValueError): сам.прочитать({})

    def test_сдвиг_байтов_при_прежней_метке_всё_равно_отказывает(сам):
        метка=основание.читатель._метка(сам.путь.stat())
        with основание._ПредставленияПрефиксов() as область, mock.patch.object(
                основание.читатель,'_метка',return_value=метка):
            сам.прочитать(область)
            сам.путь.write_bytes(сам.сырые.replace(b'old',b'new'))
            with сам.assertRaises(ValueError): сам.прочитать(область)

    def test_смена_идентичности_прав_или_числа_ссылок_отказывает(сам):
        for случай in ('идентичность','права','ссылка'):
            with сам.subTest(случай=случай):
                сам.путь.chmod(0o600); сам.путь.write_bytes(сам.сырые)
                with основание._ПредставленияПрефиксов() as область:
                    сам.прочитать(область)
                    if случай=='идентичность':
                        новый=сам.папка/'новый'; новый.write_bytes(сам.сырые)
                        os.replace(новый,сам.путь)
                    elif случай=='права': сам.путь.chmod(0o400)
                    else: os.link(сам.путь,сам.папка/'ссылка')
                    with сам.assertRaises(ValueError): сам.прочитать(область)

    def test_чужая_задача_контекст_или_реализация_не_принимаются(сам):
        with основание._ПредставленияПрефиксов() as область:
            сам.прочитать(область)
            with сам.assertRaises(ValueError):
                сам.прочитать(область,задача='00000000-0000-4000-8000-000000000002')
            чужой=copy.deepcopy(сам.контекст); чужой['sha256']='0'*64
            with сам.assertRaises(ValueError): сам.прочитать(область,контекст=чужой)
            with mock.patch.object(основание.читатель,'_РЕАЛИЗАЦИЯ','0'*64):
                with сам.assertRaises(ValueError): сам.прочитать(область)

    def test_публичный_план_не_принимает_область_другой_операции(сам):
        with основание._ПредставленияПрефиксов() as область:
            with сам.assertRaises(TypeError):
                историческое.построить_план({},представления=область)



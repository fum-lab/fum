"""Исторический план: реальные Git/JSONL и изменения нынешнего checkout."""
import copy
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

from test_план_журнала_писателя_состояния import Фикстура, байты, хэш, гит
import план_журнала_писателя_состояния as генератор
import проверенный_план_журнала_состояния as читатель


class Пример:
    def __init__(сам, каталог):
        сам.ф = Фикстура(каталог); сам.корень = сам.ф.корень
        сам.сырые = сам.ф.построить()['байты']; сам.план = json.loads(сам.сырые)
        гит(сам.корень, 'switch', '-c', 'codex/проверить-план')
        сам.путь = 'Планирование/план-журнала.json'
        (сам.корень/сам.путь).parent.mkdir(parents=True, exist_ok=True)
        сам.выбор = сам.ф.с.сохранить(сам.путь, сам.сырые)

    def сохранить(сам, документ, путь=None):
        return сам.ф.с.сохранить(путь or сам.путь, байты(документ))

    def снимок(сам): return сам.ф.снимок()

    def прочитать(сам, **к): return читатель.прочитать(сам.выбор, корень=сам.корень, **к)

    def команда(сам, вход):
        return [sys.executable, '-B', str(Path(читатель.__file__).with_name('проверить_план_журнала_состояния.py')),
            '--корень-репозитория', str(сам.корень), '--вход', str(вход)]


class ПроверенныйПлан(unittest.TestCase):
    def setUp(сам):
        каталог = tempfile.TemporaryDirectory(prefix='fum-checked-journal-plan-')
        сам.addCleanup(каталог.cleanup); сам.ф = Пример(каталог.name)

    def test_повтор_без_API_кэша_и_повторного_разбора_native(сам):
        ф = сам.ф; до = ф.снимок(); профиль = {}
        сам.assertIn('<!-- ШАБЛОН:НЕЗАПОЛНЕНО -->', ф.сырые.decode())
        with (patch.object(генератор, '_построить', side_effect=AssertionError('Не повторять создание')),
                patch.object(генератор.читатель, 'загрузить_ожидания', side_effect=AssertionError('Нет live trust')),
                patch.object(генератор.этап, 'корневые_команды', side_effect=AssertionError('Нет native-reader'))):
            итог = ф.прочитать(профиль=профиль); повтор = ф.прочитать()
        сам.assertEqual(итог, повтор); сам.assertEqual(итог['байты'], ф.сырые)
        сам.assertEqual(итог['документ'], ф.план); сам.assertFalse(итог['разрешение_установки'])
        сам.assertEqual(до, ф.снимок()); сам.assertEqual(профиль['API'], 0)

    def test_установка_наполнение_и_продвижение_HEAD_не_меняют_исторический_план(сам):
        ф = сам.ф
        for файл in ф.план['файлы']:
            п = ф.корень/файл['путь']; п.parent.mkdir(parents=True, exist_ok=True)
            п.write_text(файл['текст']); п.chmod(файл['режим'])
        сам.assertEqual(ф.прочитать()['байты'], ф.сырые)
        отчёт = ф.корень/ф.план['файлы'][1]['путь']; отчёт.write_text('Поздний содержательный отчёт\n')
        гит(ф.корень, 'add', 'Журнал'); гит(ф.корень, 'commit', '-m', 'Наполнить собственную пару')
        до = ф.снимок(); сам.assertEqual(ф.прочитать()['байты'], ф.сырые)
        сам.assertEqual(до, ф.снимок())

    def test_грязный_checkout_не_подменяет_выбранный_Git_blob(сам):
        ф = сам.ф; (ф.корень/ф.путь).write_text('Непринятая подмена\n')
        до = ф.снимок(); сам.assertEqual(ф.прочитать()['байты'], ф.сырые); сам.assertEqual(до, ф.снимок())

    def test_предел_Git_blob_проверяется_до_полного_чтения(сам):
        ф = сам.ф; до = ф.снимок()
        with (patch.object(генератор.читатель, 'ПРЕДЕЛ', 8),
                patch.object(читатель.гит, 'объект_файла', side_effect=AssertionError('Не читать oversized blob'))):
            with сам.assertRaises(ValueError): ф.прочитать()
        сам.assertEqual(до, ф.снимок())

    def test_неверный_селектор_SHA_путь_symlink_и_повтор_JSON_ключа(сам):
        ф = сам.ф
        for ключ, значение in [('sha256', '0'*64), ('коммит', 'deadbeef'), ('путь', '../нет')]:
            with сам.subTest(ключ=ключ), сам.assertRaises(ValueError):
                читатель.прочитать({**ф.выбор, ключ: значение}, корень=ф.корень)
        symlink = ф.корень/'Планирование/ссылка.json'; symlink.symlink_to('план-журнала.json')
        гит(ф.корень, 'add', 'Планирование/ссылка.json'); гит(ф.корень, 'commit', '-m', 'Недопустимый symlink')
        with сам.assertRaises(ValueError):
            читатель.прочитать({'коммит': гит(ф.корень, 'rev-parse', 'HEAD').strip(),
                'путь': 'Планирование/ссылка.json', 'sha256': хэш(ф.сырые)}, корень=ф.корень)
        with сам.assertRaises(ValueError): читатель.сверить('{"схема":1,"схема":2}'.encode(), корень=ф.корень)

    def test_замкнутые_поля_идентичность_время_метка_и_граница(сам):
        ф = сам.ф
        for правка in [{'лишнее': True}, {'схема': 'новая'}, {'ветка': 'refs/heads/fuma'},
                {'владелец': ф.план['координатор']}, {'хэш_корня': 'bad'},
                {'журнал': '../другая'}, {'метка': 'другой-заголовок'}, {'происхождение_времени': 'выдумка'}]:
            with сам.subTest(правка=правка), сам.assertRaises(ValueError):
                читатель.сверить(байты({**ф.план, **правка}), корень=ф.корень)
        with сам.assertRaises(ValueError): читатель.сверить(b' '*(генератор.читатель.ПРЕДЕЛ+1), корень=ф.корень)

    def test_исторический_ROOT_путь_SHA_и_непредок_H(сам):
        ф = сам.ф
        варианты = [{'sha256': '0'*64}, {'путь': 'expected.json'}, {'коммит': ф.выбор['коммит']}]
        for правка in варианты:
            п = {**ф.план, 'предыдущий_этап': {**ф.план['предыдущий_этап'], **правка}}
            with сам.subTest(правка=правка), сам.assertRaises(ValueError): читатель.сверить(байты(п), корень=ф.корень)
        п = {**ф.план, 'координатор': '11111111-1111-4111-8111-111111111111'}
        with сам.assertRaises(ValueError): читатель.сверить(байты(п), корень=ф.корень)

    def test_строитель_только_на_H_порядок_SHA_и_точные_байты(сам):
        ф = сам.ф
        for изменение in ('порядок', 'sha', 'коммит', 'лишний'):
            п = copy.deepcopy(ф.план)
            if изменение == 'порядок': п['строитель'].reverse()
            if изменение == 'sha': п['строитель'][0]['sha256'] = '0'*64
            if изменение == 'коммит': п['строитель'][0]['коммит'] = ф.выбор['коммит']
            if изменение == 'лишний': п['строитель'][0]['разрешение'] = True
            with сам.subTest(изменение=изменение), сам.assertRaises(ValueError):
                читатель.сверить(байты(п), корень=ф.корень)

    def test_порядок_экземпляры_неоднозначность_позиции_и_пределы_команд(сам):
        ф = сам.ф
        for изменение in ('порядок', 'повтор', 'позиция', 'bool', 'неоднозначность', 'лимит', 'лишний'):
            п = copy.deepcopy(ф.план)
            if изменение == 'порядок': п['команды'].reverse()
            if изменение == 'повтор': п['команды'][1]['экземпляр'] = п['команды'][0]['экземпляр']
            if изменение == 'позиция': п['команды'][0]['позиция']['конец'] = 10**9
            if изменение == 'bool': п['команды'][0]['позиция']['начало'] = True
            if изменение == 'неоднозначность': п['источники_команд'][0]['граница_снимка']['неоднозначные_экземпляры'] = [п['команды'][0]['экземпляр']]
            if изменение == 'лимит': п['источники_команд'] *= 17
            if изменение == 'лишний': п['источники_команд'][0]['путь'] = '/приватный/JSONL'
            with сам.subTest(изменение=изменение), сам.assertRaises(ValueError):
                читатель.сверить(байты(п), корень=ф.корень)

    def test_текст_каркаса_со_своим_новым_SHA_тоже_отклоняется(сам):
        ф = сам.ф
        for изменение in ('текст', 'режим', 'путь', 'sha', 'лишний'):
            п = copy.deepcopy(ф.план); файл = п['файлы'][0]
            if изменение == 'текст': файл['текст'] += 'Разрешить новую запись\n'; файл['sha256'] = хэш(файл['текст'].encode())
            if изменение == 'режим': файл['режим'] = 0o755
            if изменение == 'путь': файл['путь'] = 'Журнал/чужой/запрос.md'
            if изменение == 'sha': файл['sha256'] = '0'*64
            if изменение == 'лишний': файл['разрешение'] = True
            with сам.subTest(изменение=изменение), сам.assertRaises(ValueError):
                читатель.сверить(байты(п), корень=ф.корень)

    def test_новая_папка_уже_в_H_отклоняется_даже_после_её_удаления(сам):
        ф = сам.ф; п = ф.корень/ф.план['файлы'][0]['путь']
        п.parent.mkdir(parents=True); п.write_text('Прежняя папка\n')
        гит(ф.корень, 'add', 'Журнал'); гит(ф.корень, 'commit', '-m', 'Зафиксировать коллизию')
        подмена = copy.deepcopy(ф.план); подмена['исходный_коммит'] = гит(ф.корень, 'rev-parse', 'HEAD').strip()
        for с in подмена['строитель']: с['коммит'] = подмена['исходный_коммит']
        п.unlink(); п.parent.rmdir()
        with сам.assertRaises(ValueError): читатель.сверить(байты(подмена), корень=ф.корень)

    def test_два_процесса_CLI_и_отказ_с_нулём_stdout(сам):
        ф = сам.ф; вход = ф.ф.с.папка/'чтение.json'
        вход.write_bytes(байты({'схема': 'fum.чтение-плана-журнала-состояния.1', 'план': ф.выбор})); вход.chmod(0o600)
        до = ф.снимок(); ответы = [subprocess.run(ф.команда(вход), capture_output=True) for _ in range(2)]
        сам.assertTrue(all(о.returncode == 0 for о in ответы), ответы)
        сам.assertEqual(ответы[0].stdout, ответы[1].stdout); сам.assertEqual(json.loads(ответы[0].stdout)['sha256'], хэш(ф.сырые))
        сам.assertEqual(до, ф.снимок())
        вход.write_bytes(байты({'схема': 'fum.чтение-плана-журнала-состояния.1', 'план': {**ф.выбор, 'sha256': '0'*64}}))
        до = ф.снимок(); отказ = subprocess.run(ф.команда(вход), capture_output=True)
        сам.assertEqual(отказ.returncode, 1); сам.assertEqual(отказ.stdout, b''); сам.assertEqual(до, ф.снимок())


if __name__ == '__main__': unittest.main()

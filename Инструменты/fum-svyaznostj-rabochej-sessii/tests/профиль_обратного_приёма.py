"""Единичный профиль лабораторного merge и свежего читающего повтора."""
import json
import time

from test_исполнения_обратного_приёма import ИсполнениеОбратногоПриёма


def измерить():
    опыт = ИсполнениеОбратногоПриёма()
    опыт.setUp()
    try:
        начало = time.perf_counter_ns()
        результат = опыт.вызов()
        первичный = time.perf_counter_ns() - начало
        до = {п.name: п.read_bytes() for п in опыт.каталог.iterdir()}
        начало = time.perf_counter_ns()
        повтор = опыт.вызов("повтор")
        повторный = time.perf_counter_ns() - начало
        assert повтор == результат
        assert до == {п.name: п.read_bytes() for п in опыт.каталог.iterdir()}
        квитанция = json.loads((опыт.каталог / "квитанция.json").read_bytes())
        return {"схема": "fum.профиль-ядра-обратного-приёма.1", "опытов": 1,
                "первичный_нс": первичный, "повторный_нс": повторный,
                "вложенные_стадии": квитанция["профиль"],
                "новых_коммитов": 1, "равенство_результата": True,
                "повтор_без_записи": True,
                "граница": "Локальная синтетическая Git-фикстура; без ROOT-приёмки, сети и полного прогона. "
                           "Создание фикстуры вне интервалов. Вложенные стадии не суммируются с общим временем. "
                           "Ускорение производственной интеграции не измерено."}
    finally:
        опыт.doCleanups()


if __name__ == "__main__":
    print(json.dumps(измерить(), ensure_ascii=False, sort_keys=True))

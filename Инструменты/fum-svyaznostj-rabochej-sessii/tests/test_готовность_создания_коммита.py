"""Готовность обязательна для нового Git-коммита и не мешает его восстановлению."""
import copy
import contextlib
import io
import json
from pathlib import Path
import unittest
from unittest import mock

import test_создание_коммита as основа


class ГотовностьСозданияКоммита(unittest.TestCase):
    def setUp(сам):
        сам.пример = основа.СозданиеКоммита()
        сам.пример.setUp()
        сам.addCleanup(сам.пример.doCleanups)
        сам.к = основа.коммит
        сам.пример.готовить(объявить_готовность=False)
        сам.путь = Path(сам.пример.параметры["подготовка"])

    def test_отсутствующая_готовность_запрещает_git(сам):
        with mock.patch.object(сам.к, "проверки", side_effect=AssertionError("Ранний отказ не должен читать проверки")):
            сам.пример.отказ_без_коммита(сам.пример.создать)
        сам.assertFalse(Path(сам.пример.параметры["квитанция"]).exists())

    def test_отозванная_готовность_отказывает_до_дорогих_проверок(сам):
        сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        сам.к.отозвать_готовность(сам.путь, 0, "Исправить замечание")
        with mock.patch.object(сам.к, "проверки", side_effect=AssertionError("Отзыв должен проверяться раньше")):
            сам.пример.отказ_без_коммита(сам.пример.создать)

    def test_вариант_корня_не_создаёт_новую_готовность(сам):
        первый = сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        параметры = copy.deepcopy(сам.пример.параметры)
        параметры["корень"] += "/"
        for ключ in ("подготовка", "сообщение", "квитанция"):
            параметры[ключ] += ".иной-корень"
        сам.пример.отказ_без_коммита(lambda: сам.к.подготовить(параметры, сохранить_историю=True))
        сохранённое = сам.к.готовность.прочитать(Path(первый["путь"]))
        сам.assertEqual(первый["готов_в_наносекундах_эпохи"], сохранённое["готов_в_наносекундах_эпохи"])

    def test_переформатированная_запись_проверки_отказывает_перед_коммитом(сам):
        сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        запись = сам.пример.запрос.parent / "материалы/запуски-проверок" / ("1_" + основа.ЗАПУСК + ".json")
        запись.write_bytes(запись.read_bytes() + b"\n")
        with contextlib.redirect_stdout(io.StringIO()):
            сам.пример.отчёты.выполнить_предпросмотр(сам.пример.корень, сам.пример.запрос)
        сам.пример.гит("add", str(сам.пример.запрос.parent))
        сам.пример.отказ_без_коммита(сам.пример.создать)
        сам.assertFalse(Path(сам.пример.параметры["квитанция"]).exists())

    def test_старую_квитанцию_v3_можно_восстановить_без_готовности(сам):
        первый = сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        итог = сам.пример.создать()
        подготовка = json.loads(сам.путь.read_bytes())
        подготовка["схема"] = "fum.подготовленный-коммит.3"
        del подготовка["готовность"]
        сам.путь.write_bytes(сам.к.байты(подготовка))
        путь_квитанции = Path(сам.пример.параметры["квитанция"])
        квитанция = json.loads(путь_квитанции.read_bytes())
        квитанция["подготовка_sha256"] = сам.к.хэш(сам.путь.read_bytes())
        квитанция.pop("готовность")
        путь_квитанции.write_bytes(сам.к.байты(квитанция))
        Path(первый["путь"]).unlink()
        сам.assertEqual(итог["коммит"], сам.пример.создать()["коммит"])

    def test_объявление_просрочка_создание_и_повтор(сам):
        первый = сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        with mock.patch.object(сам.к.готовность.time, "time_ns", return_value=первый["готов_в_наносекундах_эпохи"] + 700_000_000_000):
            итог = сам.пример.создать()
        квитанция = json.loads(Path(сам.пример.параметры["квитанция"]).read_bytes())
        сам.assertTrue(квитанция["готовность"]["задержка"])
        сам.assertEqual(итог["коммит"], сам.пример.создать()["коммит"])

    def test_повторная_подготовка_не_меняет_адрес_или_время(сам):
        первый = сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        параметры = copy.deepcopy(сам.пример.параметры)
        for ключ in ("подготовка", "сообщение", "квитанция"):
            параметры[ключ] += ".повтор"
        сам.к.подготовить(параметры, сохранить_историю=True)
        второй = сам.к.объявить_готовность(Path(параметры["подготовка"]), [основа.ЗАПУСК], 600)
        сам.assertEqual(первый["готов_в_наносекундах_эпохи"], второй["готов_в_наносекундах_эпохи"])
        сам.assertEqual(первый["путь"], второй["путь"])

    def test_отзыв_и_новое_поколение_сохраняют_время(сам):
        первый = сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        сам.к.отозвать_готовность(сам.путь, 0, "Перепроверить отчёт")
        сам.пример.отказ_без_коммита(сам.пример.создать)
        второй = сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        сам.assertEqual(1, второй["поколение"])
        сам.assertEqual(первый["готов_в_наносекундах_эпохи"], второй["готов_в_наносекундах_эпохи"])
        сам.пример.создать()

    def test_новая_содержательная_цель_не_проходит_повторную_подготовку(сам):
        сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        параметры = copy.deepcopy(сам.пример.параметры)
        параметры["разрешённые_цели"].append("поздняя-задача.swift")
        for ключ in ("подготовка", "сообщение", "квитанция"):
            параметры[ключ] += ".другой"
        сам.пример.отказ_без_коммита(lambda: сам.к.подготовить(параметры, сохранить_историю=True))

    def test_повреждённая_готовность_не_пересоздаётся(сам):
        первый = сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)
        Path(первый["путь"]).write_bytes(b'{"')
        сам.пример.отказ_без_коммита(сам.пример.создать)
        with сам.assertRaises(сам.к.ОшибкаКоммита):
            сам.к.объявить_готовность(сам.путь, [основа.ЗАПУСК], 600)

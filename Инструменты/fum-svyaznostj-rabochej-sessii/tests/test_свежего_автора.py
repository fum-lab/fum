"""Свежий Codex и буквальный исторический повтор на настоящем Git."""
import copy
import json
from pathlib import Path
import subprocess
import unittest
from unittest import mock

import test_создание_коммита as база


class СвежийАвтор(unittest.TestCase):
    def фикстура(сам):
        ф = база.СозданиеКоммита()
        ф.setUp()
        сам.addCleanup(ф.doCleanups)
        return ф

    def снимок(сам, ф):
        файлы = [Path(ф.параметры[к]) for к in ('сообщение', 'подготовка', 'квитанция', 'кэш_модели')]
        файлы.append(ф.корень / ф.параметры['история_модели'])
        return {
            'индекс': (ф.корень / '.git/index').read_bytes(),
            'refs': ф.гит('show-ref'),
            'HEAD': ф.гит('rev-parse', 'HEAD'),
            'файлы': {str(п): п.read_bytes() if п.exists() else None for п in файлы},
        }

    def test_подготовка_отказывает_старой_роли_до_записей_во_всех_схемах(сам):
        for версия in (2, 5, 7, 8):
            for повтор in (False, True):
                with сам.subTest(версия=версия, повтор=повтор):
                    ф = сам.фикстура()
                    п = copy.deepcopy(ф.параметры)
                    п['схема'] = f'fum.создание-коммита.{версия}'
                    п['имя_автора'] = 'FUM Разработчик'
                    if версия in (7, 8):
                        п.update(исполнитель=база.ЗАДАЧА, выбранное_поручение={})
                    до = сам.снимок(ф)
                    with mock.patch.object(база.коммит, 'наблюдать_модель', side_effect=AssertionError('Импорт до отказа')) as модель:
                        with сам.assertRaisesRegex(база.коммит.ОшибкаКоммита, 'FUM Codex'):
                            база.коммит.подготовить(п, сохранить_историю=повтор)
                    модель.assert_not_called()
                    сам.assertEqual(до, сам.снимок(ф))
                    ф.doCleanups()

    def test_готовность_не_разрешает_согласованную_старую_роль(сам):
        ф = сам.фикстура(); ф.готовить(объявить_готовность=False)
        путь = Path(ф.параметры['подготовка'])
        п = json.loads(путь.read_bytes())
        п['параметры']['имя_автора'] = 'FUM Разработчик'
        п['имя_автора'] = 'FUM Разработчик [gpt-6-astra; effort=ultra]'
        путь.write_bytes(база.коммит.байты(п))
        with mock.patch.object(база.коммит.готовность, 'объявить', side_effect=AssertionError('Запись READY')) as готовность:
            with сам.assertRaisesRegex(база.коммит.ОшибкаКоммита, 'FUM Codex'):
                база.коммит.объявить_готовность(путь, [база.ЗАПУСК], 600)
        готовность.assert_not_called()
        сам.assertFalse(база.коммит.готовность.путь_этапа(ф.параметры).exists())

    def test_готовность_сверяет_весь_подготовленный_автор(сам):
        for имя in ('FUM Писатель [gpt-6-astra; effort=ultra]', 'FUM Codex', 'FUM Codex [gpt-6-astra; effort=low]'):
            with сам.subTest(имя=имя):
                ф = сам.фикстура(); ф.готовить(объявить_готовность=False)
                путь = Path(ф.параметры['подготовка']); п = json.loads(путь.read_bytes())
                п['имя_автора'] = имя; путь.write_bytes(база.коммит.байты(п))
                with сам.assertRaisesRegex(база.коммит.ОшибкаКоммита, 'автор'):
                    база.коммит.объявить_готовность(путь, [база.ЗАПУСК], 600)
                сам.assertFalse(база.коммит.готовность.путь_этапа(ф.параметры).exists())
                ф.doCleanups()

    def test_готовая_старая_роль_не_достигает_записи_дерева(сам):
        ф = сам.фикстура(); ф.готовить()
        путь = Path(ф.параметры['подготовка']); п = json.loads(путь.read_bytes())
        п['параметры']['имя_автора'] = 'FUM Разработчик'
        п['имя_автора'] = 'FUM Разработчик [gpt-6-astra; effort=ultra]'
        путь.write_bytes(база.коммит.байты(п)); до = сам.снимок(ф)
        with mock.patch.object(база.коммит, 'гит', wraps=база.коммит.гит) as гит:
            with сам.assertRaisesRegex(база.коммит.ОшибкаКоммита, 'FUM Codex'):
                ф.создать()
        сам.assertFalse(any(в.args[1] in ('write-tree', 'commit') for в in гит.call_args_list))
        сам.assertEqual(до, сам.снимок(ф))

    def исторический_результат(сам, ф, роль='FUM Разработчик', созданный=None):
        if созданный is None:
            ф.готовить(); созданный = ф.создать()
        итог = созданный
        сырой = ф.гит('cat-file', 'commit', итог['коммит'])
        сырой = сырой.replace('author FUM Codex [', 'author ' + роль + ' [', 1)
        прежний = subprocess.check_output(['git', '-C', str(ф.корень), 'hash-object', '-t', 'commit', '-w', '--stdin'], input=сырой, text=True).strip()
        ф.гит('update-ref', ф.параметры['ветка'], прежний, итог['коммит'])
        подготовка = Path(ф.параметры['подготовка']); п = json.loads(подготовка.read_bytes())
        п['параметры']['имя_автора'] = роль
        п['имя_автора'] = роль + ' [gpt-6-astra; effort=ultra]'
        подготовка.write_bytes(база.коммит.байты(п))
        квитанция = Path(ф.параметры['квитанция']); к = json.loads(квитанция.read_bytes())
        к['подготовка_sha256'] = база.коммит.хэш(подготовка.read_bytes())
        к['ожидание']['автор'][0] = п['имя_автора']
        к['результат'] = база.коммит.проверить_объект(ф.корень, к['ожидание'], прежний)
        к['наблюдённый_коммит'] = прежний
        квитанция.write_bytes(база.коммит.байты(к))
        return к['результат']

    def test_исторический_Разработчик_повторяется_перед_свежим_допуском(сам):
        ф = сам.фикстура(); итог = сам.исторический_результат(ф)
        до = сам.снимок(ф)
        with mock.patch.object(база.коммит, 'проверить_свежего_автора', side_effect=AssertionError('Свежий допуск при повторе'), create=True), \
             mock.patch.object(база.коммит, 'наблюдать_модель', side_effect=AssertionError('Импорт при повторе')), \
             mock.patch.object(база.коммит.сообщения, '_установить', side_effect=AssertionError('Установка при повторе')):
            сам.assertEqual(итог, ф.создать())
        сам.assertEqual(до, сам.снимок(ф))
        файл_квитанции = Path(ф.параметры['квитанция']); ст = файл_квитанции.stat(); сырые = файл_квитанции.read_bytes()
        ответ = subprocess.run(ф.команда_CLI('создать', '--подготовка', ф.параметры['подготовка'], '--проверка', база.ЗАПУСК), capture_output=True, text=True)
        сам.assertEqual(0, ответ.returncode, ответ.stderr)
        сам.assertEqual(итог, json.loads(ответ.stdout))
        после = файл_квитанции.stat()
        сам.assertEqual((сырые, ст.st_mode, ст.st_mtime_ns, ст.st_ino), (файл_квитанции.read_bytes(), после.st_mode, после.st_mtime_ns, после.st_ino))
        сам.assertEqual(до, сам.снимок(ф))

    def test_неуспешная_историческая_квитанция_не_разрешает_новый_эффект(сам):
        ф = сам.фикстура(); сам.исторический_результат(ф)
        путь = Path(ф.параметры['квитанция']); к = json.loads(путь.read_bytes()); к['состояние'] = 'намерение'
        путь.write_bytes(база.коммит.байты(к)); до = сам.снимок(ф)
        with mock.patch.object(база.коммит, 'проверить_свежего_автора', side_effect=AssertionError('Переход к новому эффекту'), create=True):
            ф.отказ_без_коммита(ф.создать)
        сам.assertEqual(до, сам.снимок(ф))

    def test_готовность_всех_схем_отказывает_до_живого_допуска(сам):
        for вход, выход in ((2, 4), (5, 7), (7, 9), (8, 10)):
            with сам.subTest(вход=вход):
                ф = сам.фикстура(); ф.готовить(объявить_готовность=False)
                файл = Path(ф.параметры['подготовка']); п = json.loads(файл.read_bytes())
                п['схема'] = f'fum.подготовленный-коммит.{выход}'
                п['параметры']['схема'] = f'fum.создание-коммита.{вход}'
                п['параметры']['имя_автора'] = 'FUM Разработчик'
                п['имя_автора'] = 'FUM Разработчик [gpt-6-astra; effort=ultra]'
                if вход in (7, 8): п['привязка_поручения'] = {}
                файл.write_bytes(база.коммит.байты(п)); до = сам.снимок(ф)
                with mock.patch.object(база.коммит, 'сверить_обычное_поручение', side_effect=AssertionError('Живой допуск раньше имени')):
                    with сам.assertRaisesRegex(база.коммит.ОшибкаКоммита, 'FUM Codex'):
                        база.коммит.прочитать_подготовку_готовности(файл)
                сам.assertEqual(до, сам.снимок(ф)); ф.doCleanups()

    def test_новые_дочерние_эффекты_со_старым_автором_отказаны(сам):
        import test_обычной_дочерней_точки as дочерняя
        import test_ветка_состояния_узла as состояние
        for версия in (7, 8):
            with сам.subTest(версия=версия):
                стенд = дочерняя.ОбычнаяДочерняяТочка() if версия == 7 else состояние.ВеткаСостоянияУзла()
                стенд.setUp(); сам.addCleanup(стенд.doCleanups)
                if версия == 7:
                    стенд.готовить(); ф = стенд.фикстура; п = стенд.параметры; выбор = стенд.выбор
                else:
                    стенд.ф.установка(); стенд.ф.готовность()
                    ф = стенд.ф.ф; п = стенд.ф.о.параметры; выбор = стенд.ф.о.выбор
                файл = Path(п['подготовка']); подготовка = json.loads(файл.read_bytes())
                подготовка['параметры']['имя_автора'] = 'FUM Разработчик'
                модель = подготовка['модель']
                подготовка['имя_автора'] = база.коммит.составить_имя('FUM Разработчик', модель)
                файл.write_bytes(база.коммит.байты(подготовка))
                индекс = (ф.корень / '.git/index').read_bytes(); голова = ф.гит('rev-parse', 'HEAD')
                with mock.patch.object(база.коммит, 'гит', wraps=база.коммит.гит) as гит:
                    with сам.assertRaisesRegex(база.коммит.ОшибкаКоммита, 'FUM Codex'):
                        база.коммит.создать(файл, [база.ЗАПУСК], доверенное_поручение=выбор)
                сам.assertFalse(any(в.args[1] in ('write-tree', 'commit') for в in гит.call_args_list))
                сам.assertFalse(Path(п['квитанция']).exists())
                сам.assertEqual(индекс, (ф.корень / '.git/index').read_bytes())
                сам.assertEqual(голова, ф.гит('rev-parse', 'HEAD')); стенд.doCleanups()

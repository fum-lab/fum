    @staticmethod
    def снимок(корни):
        итог = {}
        for номер, корень in enumerate(корни):
            if not os.path.lexists(корень):
                итог[(номер, '.')] = None
                continue
            for путь in [корень, *sorted(корень.rglob('*'))]:
                с = путь.lstat()
                мета = (с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink,
                    с.st_size, с.st_mtime_ns, с.st_ctime_ns)
                содержимое = (hashlib.sha256(путь.read_bytes()).hexdigest() if stat.S_ISREG(с.st_mode)
                    else os.readlink(путь) if stat.S_ISLNK(с.st_mode) else None)
                итог[(номер, путь.relative_to(корень).as_posix())] = (мета, содержимое)
        return итог


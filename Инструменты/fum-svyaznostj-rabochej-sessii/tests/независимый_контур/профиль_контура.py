def часы():
    дети = resource.getrusage(resource.RUSAGE_CHILDREN)
    return time.perf_counter_ns(), time.process_time_ns(), round((дети.ru_utime + дети.ru_stime) * 1_000_000_000)


def интервал(начало):
    конец = часы()
    return dict(zip(('по_часам_нс', 'собственный_процессор_нс', 'процессор_завершившихся_потомков_нс'),
        (б - а for а, б in zip(начало, конец))))


def собрать_метрики(результат):
    найденные = {}
    прямых_каналов = 0
    def записи_строк(текст):
        записи = []
        for строка in текст.splitlines():
            if строка.startswith('{') and 'fum.профиль-запуска-независимого-контура.1' in строка:
                запись = json.loads(строка)
                if запись.get('схема') == 'fum.профиль-запуска-независимого-контура.1': записи.append(запись)
        return записи
    def канал(сырые):
        текст = сырые.decode('utf-8')
        for запись in записи_строк(текст):
            прежняя = найденные.setdefault(запись['процесс'], запись)
            if прежняя != запись: raise ValueError('две разные метрики одного PID')
        try: значение = json.loads(текст)
        except json.JSONDecodeError: return
        обойти(значение)
    def обойти(значение):
        nonlocal прямых_каналов
        if type(значение) is dict:
            if type(значение.get('каналы')) is dict:
                for имя in ('stdout', 'stderr'):
                    запись = значение['каналы'][имя]
                    сырые = base64.b64decode(запись['base64'], validate=True)
                    if len(сырые) != запись['байтов'] or hashlib.sha256(сырые).hexdigest() != запись['sha256']:
                        raise ValueError('повреждён точный канал фасада')
                    команда = значение.get('аргументы')
                    if type(команда) is not list or not команда or команда[0] not in {'git', sys.executable}:
                        raise ValueError('неизвестный вид процесса в канале фасада')
                    if имя == 'stderr' and команда[0] == sys.executable:
                        прямые = записи_строк(сырые.decode('utf-8'))
                        if not прямые or прямые[-1]['стадия'] != 'cli' or прямые[-1]['код'] != значение['код']:
                            raise ValueError('нет метрики выбранного CLI в канале фасада')
                        прямых_каналов += 1
                    канал(сырые)
            for ключ, ребёнок in значение.items():
                if ключ not in {'stdout', 'stderr', 'каналы'}: обойти(ребёнок)
        elif type(значение) is list:
            for ребёнок in значение: обойти(ребёнок)
    канал(результат.stderr); канал(результат.stdout)
    этап = результат.args[результат.args.index('--этап') + 1]
    верхние = [з for з in найденные.values() if з['стадия'] == этап]
    if len(верхние) != 1 or верхние[0]['процесс'] != результат.процесс or верхние[0]['код'] != результат.returncode:
        raise ValueError('нет однозначной метрики настоящего верхнего процесса')
    if этап == 'выполнить' and not прямых_каналов: raise ValueError('не охвачены дочерние каналы фасада')
    return list(найденные.values())


def сравнить_чтения(стенд, число):
    """Одинаковый неизменённый engine; меняются только добавочные сверки."""
    корень = стенд['код']; профиль = стенд['профиль']
    для_сравнения = {}
    for модуль in (конструктор, допуск):
        путь_модуля = Path(модуль.__file__)
        относительный = 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/' + путь_модуля.name
        сырые = путь_модуля.read_bytes()
        if сырые != (корень / относительный).read_bytes(): raise ValueError('импортированный измеритель отличается от K')
        для_сравнения[относительный] = hashlib.sha256(сырые).hexdigest()
    выбор = конструктор.разобрать(профиль)['выбор']
    выбор['команды'] = стенд['настройки']['команды']
    итог = конструктор.построить(корень, стенд['коммит_кода'], выбор, профиль=профиль,
        независимый_sha256=hashlib.sha256(профиль).hexdigest())
    путь = корень / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/исполнение_принятого_кода.py'
    описание = importlib.util.spec_from_file_location('измеряемый_принятый_движок', путь)
    движок = importlib.util.module_from_spec(описание); описание.loader.exec_module(движок)
    движок.вызвать_гит = конструктор.гит
    код = движок.захватить_набор(корень, стенд['коммит_кода'],
        [з['путь'] for з in итог['код']] + ['Инструменты/fum-svyaznostj-rabochej-sessii/scripts/допуск_независимого_контура.py'], 'K')
    ресурсы = движок.захватить_набор(корень, стенд['коммит_кода'],
        list(dict.fromkeys([*стенд['настройки']['начальные_исходники'], *[р['путь'] for р in итог['ресурсы']]])), 'B')
    ресурсы.update(движок.захватить_набор(стенд['корень'], стенд['настройки']['данные']['коммит'], ['.gitmodules'], 'C'))
    контур = движок.Контур(код, ресурсы)
    пути = set(код) | set(ресурсы)
    байтовые = допуск.ЗакреплённыеВходы(пути)
    идентичности = допуск.ЗакреплённыеИдентичности(пути)
    наблюдения = []
    for порядок in ('АБ', 'БА', 'АБ'):
        for вариант in порядок:
            начало = часы()
            добавка = байтовые if вариант == 'А' else идентичности
            for _ in range(число):
                добавка.сверить(); контур.сверить(); добавка.сверить()
            наблюдения.append({'вариант': вариант, 'сверок': число, **интервал(начало)})
    чтений = len(код) + len(ресурсы)
    байтов = sum(len(з['байты']) for з in [*код.values(), *ресурсы.values()])
    уникальных_байтов = sum(len(з[1]) for з in байтовые.снимки.values())
    return {'наблюдения': наблюдения, 'измерители_sha256': для_сравнения,
        'движок_sha256': hashlib.sha256(путь.read_bytes()).hexdigest(),
        'за_сверку': {'А': {'полных_чтений': чтений + 2 * len(пути), 'байтов': байтов + 2 * уникальных_байтов},
            'Б': {'полных_чтений': чтений, 'байтов': байтов}},
        'граница': 'Парный компонентный опыт в тёплом кэше; не ускорение целого пути и не физический дисковый ввод.'}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--сверок', type=int, default=5)
    разбор.add_argument('--цепочка', action='store_true')
    разбор.add_argument('--свидетельства', required=True)
    параметры = разбор.parse_args()
    if not 1 <= параметры.сверок <= 100: raise ValueError('число сверок вне конечной границы')
    исходный = проверки.полный_стенд
    свидетельства = Path(параметры.свидетельства)
    метка = свидетельства.lstat()
    if (not свидетельства.is_absolute() or свидетельства.resolve() != свидетельства
        or not stat.S_ISDIR(метка.st_mode) or stat.S_IMODE(метка.st_mode) != 0o700
        or метка.st_uid != os.getuid() or any(свидетельства.iterdir())
        or any(os.path.lexists(п / '.git') for п in (свидетельства, *свидетельства.parents))):
        raise ValueError('нужен новый собственный пустой приватный каталог свидетельств 0700 вне Git')
    def сохранить(имя, сырые, режим=0o600):
        д = os.open(свидетельства / имя, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, режим)
        with os.fdopen(д, 'wb') as поток: поток.write(сырые)
    исходники = {Path(м.__file__): hashlib.sha256(Path(м.__file__).read_bytes()).hexdigest()
        for м in (sys.modules[__name__], проверки, конструктор, допуск)}
    исходники[Path(исходный.__wrapped__.__code__.co_filename)] = hashlib.sha256(
        Path(исходный.__wrapped__.__code__.co_filename).read_bytes()).hexdigest()
    результат = {'схема': 'fum.профиль-полного-лабораторного-контура.1', 'Python': sys.version,
        'платформа': platform.platform(), 'цепочка_D4': параметры.цепочка, 'стадии': [],
        'драйвер_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'проверки_sha256': hashlib.sha256(Path(проверки.__file__).read_bytes()).hexdigest(),
        'фикстура_sha256': hashlib.sha256(Path(исходный.__wrapped__.__code__.co_filename).read_bytes()).hexdigest(),
        'граница': 'Лабораторный Git. Setup включает создание K/W, leaf и завершённую D.1 либо D.4. '
            'CPU потомков включает завершившиеся Git и Python; метрики guard вложены в стадии и не суммируются с ними. '
            'Guard считает успешные повторные сверки, исключая startup/capture, предметные чтения и D.'}
    @contextlib.contextmanager
    def измеряемый(**ключи):
        начало = часы()
        with исходный(**ключи) as стенд:
            результат['стадии'].append({'стадия': 'подготовка_K_W_D', **интервал(начало)})
            результат['код'] = {'коммит': стенд['коммит_кода'],
                'профиль_sha256': hashlib.sha256(стенд['профиль']).hexdigest(),
                **конструктор.разобрать(стенд['профиль'])['происхождение'],
                'рецепт_sha256': конструктор.разобрать(стенд['профиль'])['рецепт_sha256']}
            сохранить('K-профиль.json', стенд['профиль'], 0o400)
            процесс = стенд['процесс']
            def запустить(этап, *аргументы, **именованные):
                начало = часы(); р = процесс(этап, *аргументы, **именованные)
                запись = {'стадия': этап, **интервал(начало), 'код': р.returncode, 'процесс': р.процесс,
                    'stdout_sha256': hashlib.sha256(р.stdout).hexdigest(),
                    'stderr_sha256': hashlib.sha256(р.stderr).hexdigest()}
                результат['стадии'].append(запись)
                сохранить(этап + '-stdout.bin', р.stdout); сохранить(этап + '-stderr.bin', р.stderr)
                сохранить(этап + '-свидетельство.json', конструктор.байты(запись))
                запись['guard'] = собрать_метрики(р)
                return р
            стенд['процесс'] = запустить
            yield стенд
            результат['сравнение_чтений'] = сравнить_чтения(стенд, параметры.сверок)
            начало = часы()
        результат['стадии'].append({'стадия': 'очистка_стенда', **интервал(начало)})
    начало = часы()
    try:
        with mock.patch.object(проверки, 'полный_стенд', измеряемый):
            проверки.ПолныйКорневойЦикл().полный_цикл(цепочка=параметры.цепочка)
        if any(hashlib.sha256(п.read_bytes()).hexdigest() != х for п, х in исходники.items()):
            raise ValueError('измеряемый исходник изменился во время опыта')
    except BaseException as ошибка:
        результат['весь_опыт'] = интервал(начало)
        результат['состояние'] = 'не принят'; результат['ошибка'] = str(ошибка)
        сохранить('частичный-профиль.json', конструктор.байты(результат))
        raise
    результат['весь_опыт'] = интервал(начало)
    результат['приёмка_фикстуры'] = 'Один коммит, разные PID, byte/metadata equality fresh RO replay, ноль допусков записи replay.'
    print(json.dumps(результат, ensure_ascii=False, sort_keys=True, indent=2))
    return 0



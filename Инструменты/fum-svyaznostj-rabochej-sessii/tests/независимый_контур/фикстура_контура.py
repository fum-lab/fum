def прочитать_кандидатов_цепочки():
    файл = Path(os.environ['FUM_ВЫБОР_КАНДИДАТА_ЦЕПОЧКИ'])
    сырые = файл.read_bytes()
    if hashlib.sha256(сырые).hexdigest() != os.environ['FUM_ХЭШ_ВЫБОРА_КАНДИДАТА_ЦЕПОЧКИ']:
        raise ValueError('дрейф внешнего лабораторного выбора D303')
    выбор = json.loads(сырые)
    if выбор['схема'] != 'fum.лабораторный-выбор-цепочки.1' or выбор['исходники'] != ПИНЫ_ЦЕПОЧКИ:
        raise ValueError('невыбранные candidate bytes D303')
    корень = Path(выбор['корень'])
    if not корень.is_absolute() or корень.resolve() != корень:
        raise ValueError('нефизический корень кандидатов D303')
    результат = {}
    for путь, отпечаток in ПИНЫ_ЦЕПОЧКИ.items():
        файл = корень / путь
        if файл.resolve() != файл: raise ValueError('перенаправленный кандидат D303')
        байты = файл.read_bytes()
        if hashlib.sha256(байты).hexdigest() != отпечаток:
            raise ValueError('дрейф candidate source D303: ' + путь)
        результат[путь] = байты
    return результат



"""Свежие процессы AB/BA: полный prepare против dry+transfer+prepare."""
import argparse
import json
import platform
from pathlib import Path
import statistics
import subprocess
import sys
import time
import unittest
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]/'scripts'))
import подготовка_этапа_коммита as фасад
import перенос_модели_этапа as перенос
from test_подготовки_этапа_коммита import КорневаяФикстура


def измерить(размер, вариант):
    владелец = unittest.TestCase()
    try:
        ф = КорневаяФикстура(владелец, контур='обычный')
        источник = ф.приватный/'длинная-модель.jsonl'
        д = ф.ф.источник.read_bytes()
        строка = json.dumps({'type': 'event_msg', 'payload': {'text': 'открытый префикс '*64}}, ensure_ascii=False).encode()+b'\n'
        источник.write_bytes(д + строка * max(1, (размер-len(д))//len(строка)))
        старый = ф.корень/'старая-модель.json'; старый_кэш = ф.приватный/'старая-модель-кэш.json'
        перенос.модель.импортировать(источник, ф.п['задача'], корень_репозитория=ф.корень,
            кэш=старый_кэш, история=старый)
        префикс = источник.stat().st_size
        with источник.open('ab') as поток:
            поток.write(json.dumps({'type': 'turn_context', 'timestamp': '2026-09-15T20:02:00Z',
                'payload': {'model': 'gpt-6-astra', 'effort': 'ultra'}}).encode()+b'\n')
        ф.п['источник_модели'] = str(источник)
        ф.ф.гит('add', 'старая-модель.json'); ф.ф.гит('commit', '-qm', 'Старый снимок открытого профиля')
        ф.п['исходный_коммит'] = ф.ф.гит('rev-parse', 'HEAD').strip(); ф.п['родители'] = [ф.п['исходный_коммит']]
        т = {к: {'путь': str(п), 'sha256': перенос.хэш(п.read_bytes())}
            for к, п in [('прежняя_история', старый), ('прежний_кэш', старый_кэш)]}
        прежние = [п.read_bytes() for п in (старый, старый_кэш)]
        код = перенос.замыкание_кода()
        метка = перенос.чтение._метка(источник.stat())
        стадии = []; наблюдения = []; разборы = 0; сохранённая_строка = 0
        байты_кода = 0; байты_снимков = 0; байты_пары = 0
        снимок = перенос.снимок; прочитать = перенос.модель._прочитать
        def чтение_снимка(путь):
            nonlocal байты_кода, байты_снимков
            р = снимок(путь)
            if Path(р['путь']).is_relative_to(перенос.ИНСТРУМЕНТЫ): байты_кода += р['метка'][2]
            else: байты_снимков += р['метка'][2]
            return р
        def чтение_пары(*а, **к):
            nonlocal байты_пары
            р = прочитать(*а, **к); байты_пары += len(р); return р
        разбор = перенос.чтение._разобрать
        последний = перенос.перенос._сверить_последнее_наблюдение
        наблюдать = фасад.коммит.наблюдать_модель
        def разобрать(д):
            nonlocal разборы
            if д.endswith(b'\n') and b'\n' not in д[:-1] and b'"type"' in д:
                разборы += 1
            return разбор(д)
        def сверить_последнее(поток, прежняя):
            nonlocal сохранённая_строка
            поз = прежняя['последнее']['позиция']
            сохранённая_строка += поз['конец']-поз['начало']
            return последний(поток, прежняя)
        def наблюдение(*а, **к):
            н = time.perf_counter_ns(); р = наблюдать(*а, **к)
            наблюдения.append({'наносекунды': time.perf_counter_ns()-н, 'профиль': р['профиль']})
            return р
        def стадия(имя, действие):
            н = time.perf_counter_ns(); р = действие()
            стадии.append({'имя': имя, 'наносекунды': time.perf_counter_ns()-н,
                **({'профиль': р['профиль']} if type(р) is dict and 'профиль' in р else {})})
            return р
        with patch.object(перенос.чтение, '_разобрать', side_effect=разобрать), \
                patch.object(перенос.перенос, '_сверить_последнее_наблюдение', side_effect=сверить_последнее), \
                patch.object(фасад.коммит, 'наблюдать_модель', side_effect=наблюдение), \
                patch.object(перенос, 'снимок', side_effect=чтение_снимка), \
                patch.object(перенос.модель, '_прочитать', side_effect=чтение_пары):
            начало = time.perf_counter_ns()
            план = стадия('Предварительная сверка переноса', lambda: перенос.предварить(ф.п, т)) if вариант == 'B' else None
            стадия('Штатный start', lambda: фасад.каркас.start_session(ф.корень, ф.stem,
                ф.вход['начало']['метка'], ф.п['заголовок'], ф.п['задача'], ф.сообщения))
            стадия('Штатный mkdir', lambda: (ф.корень/ф.п['история_модели']).parent.mkdir(mode=0o755))
            if вариант == 'B': перенос.выполнить(ф.п, т, план, вызов=стадия)
            подготовка = стадия('Обычный prepare', lambda: фасад.коммит.подготовить(ф.п))
            полное_время = time.perf_counter_ns()-начало
        новая = (ф.корень/ф.п['история_модели']).read_bytes()
        перенос.модель.импортировать(источник, ф.п['задача'], корень_репозитория=ф.корень,
            кэш=ф.приватный/'независимый-кэш.json', история=ф.корень/'независимая.json')
        assert новая == (ф.корень/'независимая.json').read_bytes()
        assert прежние == [п.read_bytes() for п in (старый, старый_кэш)]
        после = перенос.замыкание_кода()
        assert код == после, ([з['путь'] for з in после if з not in код], [з['путь'] for з in код if з not in после])
        assert метка == перенос.чтение._метка(источник.stat())
        native_bytes = сохранённая_строка + sum(з.get('профиль', {}).get('прочитано_байтов', 0) for з in стадии) \
            + sum(з['профиль']['прочитано_байтов'] for з in наблюдения)
        h = json.loads(новая)
        return {'вариант': вариант, 'байтов_префикса': префикс, 'байтов_источника': источник.stat().st_size,
            'источник_sha256': перенос.хэш(источник.read_bytes()), 'полное_время_нс': полное_время,
            'стадии': стадии, 'модель_в_prepare': наблюдения, 'логических_байтов_native': native_bytes,
            'добавочных_байтов_сохранённого_наблюдения': сохранённая_строка, 'разобрано_native_строк': разборы,
            'прочитано_байтов_кода_в_таймере': байты_кода,
            'прочитано_байтов_снимков_пары_в_таймере': байты_снимков,
            'прочитано_байтов_обычного_чтения_пары_в_таймере': байты_пары,
            'прочие_чтения_prepare': None,
            'полных_SHA_префикса': 2 if вариант == 'B' else 1,
            'история_sha256': перенос.хэш(новая), 'наблюдений': h['число_наблюдений'],
            'последнее': h['последнее'], 'готовность': False,
            'байтов_кода_за_одну_сверку': sum(з['метка'][2] for з in код),
            'код': {Path(з['путь']).relative_to(перенос.ИНСТРУМЕНТЫ).as_posix(): з['sha256'] for з in код},
            'код_профилировщика_и_фикстур': {ф.relative_to(перенос.ИНСТРУМЕНТЫ).as_posix(): перенос.хэш(ф.read_bytes())
                for ф in (Path(__file__).resolve(), Path(__file__).with_name('test_подготовки_этапа_коммита.py'),
                    Path(__file__).with_name('test_создание_коммита.py'))},
            'старые_байты_неизменны': True, 'совпадает_с_независимым_полным_импортом': True,
            'prepare_схема': подготовка['схема']}
    finally:
        владелец.doCleanups()


def главная():
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument('--работник', choices=['A', 'B']); р.add_argument('--размер', type=int)
    р.add_argument('--выход'); р.add_argument('--повторов', type=int, default=3)
    а = р.parse_args()
    if а.работник:
        print(json.dumps(измерить(а.размер, а.работник), ensure_ascii=False, sort_keys=True)); return
    if not а.выход or а.повторов < 3: р.error('нужен новый выход и хотя бы три повтора')
    выход = Path(а.выход)
    if выход.exists(): р.error('выход уже существует')
    измерения = []; пары = []
    for размер in (64*1024, 1024*1024, 16*1024*1024):
        for повтор in range(а.повторов):
            раунд = []
            for вариант in 'ABBA':
                з = subprocess.run([sys.executable, '-B', str(Path(__file__).resolve()),
                    '--работник', вариант, '--размер', str(размер)], capture_output=True)
                if з.returncode:
                    sys.stderr.buffer.write(з.stderr); raise ValueError('Работник профиля отказал')
                д = json.loads(з.stdout); д.update(размер=размер, повтор=повтор); раунд.append(д); измерения.append(д)
            for л, п in ((раунд[0], раунд[1]), (раунд[3], раунд[2])):
                assert л['источник_sha256'] == п['источник_sha256'] and л['история_sha256'] == п['история_sha256'] and л['код'] == п['код']
                пары.append({'размер': размер, 'повтор': повтор, 'порядок': 'AB' if л is раунд[0] else 'BA',
                    'A_нс': л['полное_время_нс'], 'B_нс': п['полное_время_нс'], 'отношение_B_A': п['полное_время_нс']/л['полное_время_нс']})
            print(f'Завершён размер {размер}, повтор {повтор+1}', file=sys.stderr, flush=True)
    медианы = [{'размер': размер, 'медиана_B_A': statistics.median(п['отношение_B_A'] for п in пары if п['размер']==размер)}
        for размер in sorted({п['размер'] for п in пары})]
    выигрыш = next((м['размер'] for м in медианы if м['медиана_B_A'] < 1), None)
    результат = {'схема': 'fum.парный-профиль-переноса-модели.1',
        'граница': 'Предварительная сверка B, штатные start/mkdir, dry, пересверки, write и настоящий обычный prepare. Setup, создание старой пары, независимый полный импорт, агрегация и cleanup исключены. Готовность, create, связность и весь ROOT цикл не измеряются. Вложенные интервалы не прибавляются к полному времени.',
        'вход': 'Открытая воспроизводимая фикстура JSONL, без пользовательского диалога.',
        'физический_IO': None, 'кэш_ОС': 'Не очищался; чередование AB/BA не устраняет его влияние.',
        'python': sys.version, 'система': platform.system(), 'архитектура': platform.machine(),
        'пар': пары, 'медианы': медианы, 'первый_измеренный_размер_выгоды': выигрыш,
        'порог': 'Первый измеренный размер с медианой B/A < 1; точный переход между размерами и другие машины неизвестны.',
        'измерения': измерения}
    выход.parent.mkdir(parents=True, exist_ok=True)
    with выход.open('x') as поток: json.dump(результат, поток, ensure_ascii=False, sort_keys=True, indent=2); поток.write('\n')
    print(json.dumps({'медианы': медианы, 'порог': выигрыш}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

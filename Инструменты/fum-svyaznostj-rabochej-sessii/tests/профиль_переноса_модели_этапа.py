def требовать(условие, пояснение):
    if not условие:
        raise ValueError(пояснение)


def снимок_файлов(корень, исключённый=None):
    результат = {}
    for путь in корень.rglob('*'):
        if исключённый is not None and путь.is_relative_to(исключённый):
            continue
        состояние = путь.lstat()
        требовать(stat.S_ISREG(состояние.st_mode) or stat.S_ISDIR(состояние.st_mode),
            'Неожиданный специальный узел в эффектах фикстуры')
        каталог = stat.S_ISDIR(состояние.st_mode)
        результат[путь.relative_to(корень).as_posix()] = (b'' if каталог else путь.read_bytes(),
            stat.S_IMODE(состояние.st_mode), 'каталог' if каталог else 'файл')
    return результат


def изменения_файлов(до, после):
    требовать(set(до) <= set(после), 'Операция удалила прежний файл')
    return {п: д for п, д in после.items() if до.get(п) != д}


def операция(ф, прежняя, стадия=None):
    план = перенос.предварить(ф.п, прежняя) if ф.вариант == 'B' else None
    фасад.каркас.start_session(ф.корень, ф.stem, ф.вход['начало']['метка'],
        ф.п['заголовок'], ф.п['задача'], ф.сообщения)
    (ф.корень/ф.п['история_модели']).parent.mkdir(mode=0o755)
    if ф.вариант == 'B':
        if стадия is None:
            перенос.выполнить(ф.п, прежняя, план)
        else:
            перенос.выполнить(ф.п, прежняя, план, вызов=стадия)
    return фасад.коммит.подготовить(ф.п)


def счётчики_операции(ф, прежняя):
    счётчики = {'разобрано_строк_JSONL': 0, 'байтов_последнего_наблюдения': 0,
        'байтов_кода': 0, 'байтов_снимков': 0, 'байтов_чтения_пары': 0,
        'стадии_переноса': [], 'наблюдения_prepare': []}
    разбор = перенос.чтение._разобрать
    последний = перенос.перенос._сверить_последнее_наблюдение
    наблюдать = фасад.коммит.наблюдать_модель
    снимок = перенос.снимок
    прочитать = перенос.модель._прочитать
    def разобрать(данные):
        if данные.endswith(b'\n') and b'\n' not in данные[:-1] and b'"type"' in данные:
            счётчики['разобрано_строк_JSONL'] += 1
        return разбор(данные)
    def сверить_последнее(поток, история):
        позиция = история['последнее']['позиция']
        счётчики['байтов_последнего_наблюдения'] += позиция['конец']-позиция['начало']
        return последний(поток, история)
    def наблюдение(*аргументы, **параметры):
        результат = наблюдать(*аргументы, **параметры)
        счётчики['наблюдения_prepare'].append(результат['профиль'])
        return результат
    def чтение_снимка(путь):
        результат = снимок(путь)
        имя = 'байтов_кода' if Path(результат['путь']).is_relative_to(перенос.ИНСТРУМЕНТЫ) else 'байтов_снимков'
        счётчики[имя] += результат['метка'][2]
        return результат
    def чтение_пары(*аргументы, **параметры):
        результат = прочитать(*аргументы, **параметры)
        счётчики['байтов_чтения_пары'] += len(результат)
        return результат
    def стадия(имя, действие):
        результат = действие()
        счётчики['стадии_переноса'].append({'имя': имя,
            **({'профиль': результат['профиль']} if type(результат) is dict and 'профиль' in результат else {})})
        return результат
    with ExitStack() as стек:
        for объект, имя, функция in ((перенос.чтение, '_разобрать', разобрать),
                (перенос.перенос, '_сверить_последнее_наблюдение', сверить_последнее),
                (фасад.коммит, 'наблюдать_модель', наблюдение), (перенос, 'снимок', чтение_снимка),
                (перенос.модель, '_прочитать', чтение_пары)):
            стек.enter_context(patch.object(объект, имя, side_effect=функция))
        результат = операция(ф, прежняя, стадия)
    счётчики['логических_байтов_модели'] = счётчики['байтов_последнего_наблюдения'] + sum(
        з.get('профиль', {}).get('прочитано_байтов', 0) for з in счётчики['стадии_переноса']) + sum(
        з['прочитано_байтов'] for з in счётчики['наблюдения_prepare'])
    return результат, счётчики


def подтвердить_исход(ф, подготовка, до):
    требовать(set(подготовка) == {'схема', 'подготовка', 'сообщение_sha256', 'коммит_создан'} and
        подготовка['схема'] == 'fum.результат-подготовки-коммита.1' and подготовка['коммит_создан'] is False,
        'Неверный компактный результат prepare')
    сохранённые = Path(ф.п['подготовка']).read_bytes()
    полная = перенос.чтение._разобрать(сохранённые)
    требовать(set(полная) == ПОЛЯ_ПОДГОТОВКИ and полная['схема'] == 'fum.подготовленный-коммит.7', 'Неверная полная подготовка')
    требовать(полная['параметры'] == до['параметры'] and set(полная['параметры']) == фасад.коммит.ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ,
        'Изменены параметры подготовки')
    требовать(all(set(з) == {'экземпляр', 'текст', 'позиция', 'задача'} for з in полная['команды']) and
        [з['текст'] for з in полная['команды']] == ф.сообщения, 'Изменены выбранные команды')
    новая = (ф.корень/ф.п['история_модели']).read_bytes()
    история = перенос.чтение._разобрать(новая)
    сообщение = Path(ф.п['сообщение']).read_bytes()
    требовать(полная['история_sha256'] == перенос.хэш(новая) and полная['модель'] == история['последнее'] and
        полная['наблюдений'] == история['число_наблюдений'], 'История расходится с подготовкой')
    требовать(подготовка['подготовка'] == ф.п['подготовка'] and
        подготовка['сообщение_sha256'] == полная['сообщение_sha256'] == перенос.хэш(сообщение), 'Сообщение расходится с подготовкой')
    сырая_оболочка = Path(ф.п['кэш_модели']).read_bytes()
    оболочка = перенос.чтение._разобрать(сырая_оболочка)
    требовать(set(оболочка) == {'данные', 'sha256'}, 'Неверная оболочка курсора')
    курсор = оболочка['данные']
    требовать(set(курсор) == {'история', 'метка', 'назначение', 'реализация', 'ожидаемый_sha256', 'подготовлено'} and
        оболочка['sha256'] == перенос.хэш(перенос.чтение._байты(курсор)), 'Неверные данные курсора')
    требовать(перенос.чтение._байты(курсор['история']) == новая and
        курсор['метка'] == list(перенос.чтение._метка(ф.источник.stat())) and
        курсор['назначение'] == str(ф.корень/ф.п['история_модели']) and
        курсор['реализация'] == перенос.модель._РЕАЛИЗАЦИЯ and
        курсор['подготовлено'] is False and курсор['ожидаемый_sha256'] is None, 'Курсор не подтверждён')
    def неизменны():
        требовать(до['native'] == перенос.чтение._метка(ф.источник.stat()) and
            до['native_sha256'] == перенос.хэш(ф.источник.read_bytes()), 'Изменён native')
        требовать(до['пара'] == [п.read_bytes() for п in ф.пара], 'Изменена старая пара')
        требовать(до['код'] == перенос.замыкание_кода(), 'Изменён исполняемый код')
        требовать(до['HEAD'] == ф.ф.гит('rev-parse', 'HEAD').strip() and
            до['индекс'] == (ф.корень/'.git/index').read_bytes(), 'Изменён HEAD или индекс')
    неизменны()
    готовность = фасад.коммит.готовность.путь_этапа(ф.п)
    требовать(полная['готовность'] == str(готовность) and not os.path.lexists(готовность) and
        not os.path.lexists(ф.п['квитанция']), 'Prepare создал готовность или квитанцию')
    публичные = изменения_файлов(до['публичные'], снимок_файлов(ф.корень))
    файлы = {ф.п['запрос'], str(Path(ф.п['запрос']).with_name('отчёт.md')),
        ф.п['история_модели'], ф.ф.запрос.relative_to(ф.корень).as_posix(), 'Журнал/README.md'}
    каталоги = {п.as_posix() for имя in файлы for п in Path(имя).parents
        if п.as_posix() != '.' and п.as_posix() not in до['публичные']}
    требовать(set(публичные) == файлы | каталоги and all(публичные[п][2] == 'файл' for п in файлы) and
        all(публичные[п][2] == 'каталог' for п in каталоги), 'Неожиданные публичные эффекты')
    приватные = изменения_файлов(до['приватные'], снимок_файлов(ф.приватный, ф.корень))
    ожидаемые = {Path(ф.п[ключ]).relative_to(ф.приватный).as_posix() for ключ in ('сообщение', 'подготовка', 'кэш_модели')}
    ожидаемые.add(Path(ф.п['кэш_модели']+'.lock').relative_to(ф.приватный).as_posix())
    требовать(set(приватные) == ожидаемые and Path(ф.п['кэш_модели']+'.lock').read_bytes() == b'', 'Неожиданные приватные эффекты')
    # Проверены точные адреса и stat внутри каждого работника. Только эти
    # технические величины заменяются для независимых временных каталогов.
    полная = copy.deepcopy(полная)
    for ключ in ('корень', 'источник_модели', 'кэш_модели', 'сообщение', 'подготовка', 'квитанция'):
        полная['параметры'][ключ] = '<'+ключ+'>'
    for источник in полная['параметры']['источники']:
        требовать(источник['путь'] == str(ф.ф.источник), 'Чужой источник команд')
        источник['путь'] = '<источник-команд>'
    полная['параметры']['исходный_коммит'] = '<HEAD>'
    требовать(полная['параметры']['родители'] == [до['HEAD']], 'Неверные родители')
    полная['параметры']['родители'] = ['<HEAD>']
    полная['готовность'] = '<готовность>'
    курсор = copy.deepcopy(курсор)
    курсор['назначение'] = '<история-модели>'
    курсор['метка'] = ['<dev>', '<ino>', курсор['метка'][2], '<mtime_ns>', '<ctime_ns>']
    эффекты_приватные = {}
    for путь, (данные, режим, вид) in приватные.items():
        требовать(вид == 'файл', 'Приватный эффект не является файлом')
        if путь == Path(ф.п['подготовка']).relative_to(ф.приватный).as_posix():
            содержимое = полная
        elif путь == Path(ф.п['кэш_модели']).relative_to(ф.приватный).as_posix():
            содержимое = курсор
        else:
            содержимое = {'sha256': перенос.хэш(данные), 'байты': len(данные)}
        эффекты_приватные[путь] = {'содержимое': содержимое, 'режим': режим}
    перенос.модель.импортировать(ф.источник, ф.п['задача'], корень_репозитория=ф.корень,
        кэш=ф.приватный/'независимый-кэш.json', история=ф.корень/'независимая.json')
    совпадает = новая == (ф.корень/'независимая.json').read_bytes()
    требовать(совпадает, 'История отличается от независимого полного импорта')
    неизменны()
    исход = {'байтов_префикса': ф.префикс, 'байтов_источника': ф.источник.stat().st_size,
        'источник_sha256': до['native_sha256'], 'история': история, 'история_sha256': перенос.хэш(новая),
        'сообщение_sha256': перенос.хэш(сообщение), 'сообщение': сообщение.decode(), 'подготовка': полная,
        'курсор': курсор, 'публичные_эффекты': {п: {'sha256': перенос.хэш(д), 'байты': len(д), 'режим': р, 'вид': в}
            for п, (д, р, в) in публичные.items()}, 'приватные_эффекты': эффекты_приватные,
        'код': {Path(з['путь']).relative_to(перенос.ИНСТРУМЕНТЫ).as_posix(): з['sha256'] for з in до['код']},
        'код_профиля_и_фикстур': {п.relative_to(перенос.ИНСТРУМЕНТЫ).as_posix(): перенос.хэш(п.read_bytes())
            for п in (Path(__file__).resolve(), Path(__file__).with_name('test_подготовки_этапа_коммита.py'),
                Path(__file__).with_name('test_создание_коммита.py'))},
        'старые_байты_неизменны': True, 'код_и_native_неизменны': True,
        'совпадает_с_независимым_полным_импортом': совпадает, 'готовность': False}
    свидетельства = {'HEAD': до['HEAD'], 'индекс_sha256': перенос.хэш(до['индекс']),
        'подготовка_sha256': перенос.хэш(сохранённые), 'курсор_sha256': перенос.хэш(сырая_оболочка), 'native_stat': list(до['native'])}
    return исход, свидетельства


def измерить(размер, вариант, *, режим='замер'):
    требовать(type(размер) is int and размер >= 65536 and вариант in ('A', 'B') and
        режим in ('замер', 'счётчики'), 'Неверный сценарий работника')
    владелец = unittest.TestCase()
    try:
        ф = КорневаяФикстура(владелец, контур='обычный')
        ф.вариант = вариант
        # Фиксируются будущие UUID и даты открытой фикстуры; настоящие UUID,
        # хэши native, команды, модель, режимы и эффекты не нормализуются.
        os.environ['GIT_AUTHOR_DATE'] = '2026-09-16T00:00:00+03:00'
        os.environ['GIT_COMMITTER_DATE'] = '2026-09-16T00:00:00+03:00'
        for старый, новый in zip(ф.номера, ('00000000-0000-0000-0000-000000000011',
                '00000000-0000-0000-0000-000000000012'), strict=True):
            ф.п['разрешённые_цели'] = [п.replace(старый, новый) for п in ф.п['разрешённые_цели']]
        ф.источник = ф.приватный/'длинная-модель.jsonl'
        данные = ф.ф.источник.read_bytes()
        строка = json.dumps({'type': 'event_msg', 'payload': {'text': 'открытый префикс '*64}}, ensure_ascii=False).encode()+b'\n'
        ф.источник.write_bytes(данные + строка * max(1, (размер-len(данные))//len(строка)))
        старый = ф.корень/'старая-модель.json'
        старый_кэш = ф.приватный/'старая-модель-кэш.json'
        ф.пара = (старый, старый_кэш)
        перенос.модель.импортировать(ф.источник, ф.п['задача'], корень_репозитория=ф.корень,
            кэш=старый_кэш, история=старый)
        ф.префикс = ф.источник.stat().st_size
        with ф.источник.open('ab') as поток:
            поток.write(json.dumps({'type': 'turn_context', 'timestamp': '2026-09-15T20:02:00Z',
                'payload': {'model': 'gpt-6-astra', 'effort': 'ultra'}}).encode()+b'\n')
        ф.п['источник_модели'] = str(ф.источник)
        ф.ф.гит('add', 'старая-модель.json')
        ф.ф.гит('commit', '-qm', 'Старый снимок открытого профиля')
        ф.п['исходный_коммит'] = ф.ф.гит('rev-parse', 'HEAD').strip()
        ф.п['родители'] = [ф.п['исходный_коммит']]
        прежняя = {к: {'путь': str(п), 'sha256': перенос.хэш(п.read_bytes())}
            for к, п in zip(('прежняя_история', 'прежний_кэш'), ф.пара, strict=True)}
        до = {'параметры': copy.deepcopy(ф.п), 'native': перенос.чтение._метка(ф.источник.stat()),
            'native_sha256': перенос.хэш(ф.источник.read_bytes()), 'пара': [п.read_bytes() for п in ф.пара],
            'код': перенос.замыкание_кода(), 'HEAD': ф.п['исходный_коммит'],
            'индекс': (ф.корень/'.git/index').read_bytes(), 'публичные': снимок_файлов(ф.корень),
            'приватные': снимок_файлов(ф.приватный, ф.корень)}
        if режим == 'замер':
            начало = time.perf_counter_ns()
            подготовка = операция(ф, прежняя)
            время = time.perf_counter_ns()-начало
            счётчики = None
        else:
            подготовка, счётчики = счётчики_операции(ф, прежняя)
            время = None
        исход, свидетельства = подтвердить_исход(ф, подготовка, до)
        return {'схема': 'fum.работник-профиля-переноса-модели.2', 'вариант': вариант,
            'размер': размер, 'режим': режим, 'оптимизация': sys.flags.optimize,
            'полное_время_нс': время, 'счётчики': счётчики, 'исход': исход, 'свидетельства': свидетельства}
    finally:
        владелец.doCleanups()


def проверить_выдачу(данные, размер, вариант, режим):
    требовать(type(данные) is dict and set(данные) == ПОЛЯ_ВЫДАЧИ and
        данные['схема'] == 'fum.работник-профиля-переноса-модели.2' and данные['вариант'] == вариант and
        type(данные['размер']) is int and данные['размер'] == размер and данные['режим'] == режим and
        type(данные['оптимизация']) is int and данные['оптимизация'] == 0, 'Неверная выдача работника')
    исход = данные['исход']
    требовать(type(исход) is dict and set(исход) == ПОЛЯ_ИСХОДА and исход.get('готовность') is False and all(исход.get(к) is True for к in
        ('старые_байты_неизменны', 'код_и_native_неизменны', 'совпадает_с_независимым_полным_импортом')),
        'Работник не подтвердил инварианты')
    требовать(type(исход['подготовка']) is dict and set(исход['подготовка']) == ПОЛЯ_ПОДГОТОВКИ and
        type(исход['курсор']) is dict and set(исход['курсор']) ==
        {'история', 'метка', 'назначение', 'реализация', 'ожидаемый_sha256', 'подготовлено'}, 'Неверный полный исход')
    требовать(type(исход['история']) is dict and set(исход['история']) == ПОЛЯ_ИСТОРИИ and
        type(исход['курсор']['история']) is dict and set(исход['курсор']['история']) == ПОЛЯ_ИСТОРИИ and
        type(исход['подготовка']['параметры']) is dict and set(исход['подготовка']['параметры']) ==
        фасад.коммит.ПОЛЯ_КОНТРОЛЬНОЙ_ТОЧКИ, 'Неверная вложенная история или параметры')
    for модель in (исход['подготовка']['модель'], исход['история']['последнее'], исход['курсор']['история']['последнее']):
        требовать(type(модель) is dict and set(модель) == ПОЛЯ_МОДЕЛИ and
            type(модель['позиция']) is dict and set(модель['позиция']) == {'начало', 'конец', 'sha256'},
            'Неверное наблюдение модели')
    требовать(type(исход['байтов_источника']) is int and type(исход['байтов_префикса']) is int,
        'Число байтов должно быть целым')
    требовать(type(исход['подготовка']['команды']) is list and all(type(з) is dict and
        set(з) == {'экземпляр', 'текст', 'позиция', 'задача'} and type(з['позиция']) is dict and
        set(з['позиция']) == {'начало', 'конец', 'sha256'} for з in исход['подготовка']['команды']), 'Неверные команды')
    требовать(type(данные['свидетельства']) is dict and set(данные['свидетельства']) ==
        {'HEAD', 'индекс_sha256', 'подготовка_sha256', 'курсор_sha256', 'native_stat'}, 'Неверные свидетельства')
    if режим == 'замер':
        требовать(type(данные['полное_время_нс']) is int and данные['полное_время_нс'] > 0 and
            данные['счётчики'] is None, 'Чистое время должно быть положительным целым без счётчиков')
    else:
        требовать(данные['полное_время_нс'] is None and type(данные['счётчики']) is dict and
            set(данные['счётчики']) == ПОЛЯ_СЧЁТЧИКОВ and
            type(данные['счётчики'].get('разобрано_строк_JSONL')) is int and
            данные['счётчики']['разобрано_строк_JSONL'] > 0, 'Инструментированный запуск не является замером')
    return данные


def сверить_исходы(левый, правый):
    требовать(перенос.чтение._байты(левый['исход']) == перенос.чтение._байты(правый['исход']),
        'Полные исходы A/B или замера/счётчика различаются')


def работник(размер, вариант, режим):
    запуск = subprocess.run([sys.executable, '-B', str(Path(__file__).resolve()), '--работник', вариант,
        '--размер', str(размер), '--режим', режим], capture_output=True)
    if запуск.returncode:
        sys.stderr.buffer.write(запуск.stderr)
        raise ValueError('Работник профиля отказал: '+str(запуск.returncode))
    return проверить_выдачу(перенос.чтение._разобрать(запуск.stdout), размер, вариант, режим)



"""Одинаковый контейнер, независимые процессы; вложенные интервалы не складываются."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import resource
import statistics
import subprocess
import sys
import tempfile
import time
import tracemalloc

import test_состояние_задач_узла as фикстура
import состояние_задач_узла as состояние
import каталог_наблюдений_узла as каталог


def рабочий(вход):
    параметры = json.loads(вход.read_bytes())
    контейнер = состояние.КонтейнерПроцессов(корень_данных=Path(параметры['контейнер']),
        писатель=параметры['писатель'], читатель=параметры['читатель'], корень_репозитория=Path(параметры['корень']))
    обнаружение = каталог.Каталог(контейнер, параметры['доверие'], параметры['доверие']['источник'])
    tracemalloc.start(); начало = time.monotonic_ns()
    результат = обнаружение.обнаружить()
    общее = time.monotonic_ns()-начало
    начало = time.monotonic_ns(); данные = каталог.кодировать(результат); сериализация = time.monotonic_ns()-начало
    _, пик = tracemalloc.get_traced_memory(); tracemalloc.stop()
    assert len(результат['циклы']) == 1 and результат['циклы'][0]['итог'] == 'подтверждён'
    assert all(not x['свежее_в_этом_цикле'] for x in результат['история'])
    RSS = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return {'измерения': {**обнаружение.профиль, 'обнаружение_общее_наносекунды': общее,
        'выходная_сериализация_наносекунды': сериализация, 'пик_python_байтов': пик,
        'пик_RSS_родителя_байтов': RSS if sys.platform == 'darwin' else RSS*1024},
        'выход_sha256': каталог.хэш(данные), 'выход_байтов': len(данные),
        'MCP': 0, 'send': 0, 'create': 0}


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path)
    разбор.add_argument('--повторы', type=int, default=3)
    разбор.add_argument('--рабочий', type=Path)
    параметры = разбор.parse_args()
    if параметры.рабочий:
        print(json.dumps(рабочий(параметры.рабочий), ensure_ascii=False, sort_keys=True)); return
    if параметры.выход is None or not 3 <= параметры.повторы <= 10: разбор.error('нужен выход и 3–10 повторов')
    двоичные = Path(os.environ['FUM_TEST_BIN_DIR']).resolve()
    пример = фикстура.ЦиклКонтроллера(); пример.подготовить_испытание()
    try:
        корень = пример.с.папка / 'контейнер'; корень.mkdir(mode=0o700)
        subprocess.run([str(двоичные/'писатель-контейнера'), 'удерживать', str(корень)], input=b'',
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True, timeout=60)
        контейнер = состояние.КонтейнерПроцессов(корень_данных=корень, писатель=двоичные/'писатель-контейнера',
            читатель=двоичные/'читатель-контейнера', корень_репозитория=пример.с.репо)
        цикл = состояние.ЦиклНаблюдения(пример.доверие, корень=пример.с.репо, контейнер=контейнер)
        ответ = пример.ответ(); ответ['профильная_нагрузка'] = 'я' * (256*1024)
        # Непрозрачная нагрузка остаётся RAW; её не принимают за полномочие.
        цикл.наблюдать(lambda запрос: ответ, источник='профильная фикстура; без MCP')
        вход = корень/'вход.json'; вход.write_bytes(каталог.кодировать({'контейнер':str(корень),
            'корень':str(пример.с.репо), 'писатель':str(двоичные/'писатель-контейнера'),
            'читатель':str(двоичные/'читатель-контейнера'), 'доверие':пример.доверие}))
        os.chmod(вход,0o600)
        навык = Path(__file__).resolve().parents[1]; репо = навык.parents[1]
        файлы = [Path(__file__).resolve(), навык/'scripts/каталог_наблюдений_узла.py',
            навык/'scripts/состояние_задач_узла.py', навык/'scripts/компактный_ответ_задачи.py',
            навык/'scripts/восстановление_прерванной_задачи.py',
            репо/'Приложения/FUMA/Packages/КонтейнерНаблюдений/Sources/ЧитательКонтейнера/main.swift']
        хэши = {str(x.relative_to(репо)):каталог.хэш(x.read_bytes()) for x in файлы}
        сегмент = корень/'сегмент.fumobs'; до = каталог.хэш(сегмент.read_bytes())
        запуски=[]
        for _ in range(параметры.повторы):
            ответ_процесса=subprocess.run([sys.executable,'-B',str(Path(__file__).resolve()),'--рабочий',str(вход)],
                capture_output=True,check=True,timeout=120)
            запуски.append(json.loads(ответ_процесса.stdout))
        assert len({x['выход_sha256'] for x in запуски}) == 1
        assert каталог.хэш(сегмент.read_bytes()) == до
        assert хэши == {str(x.relative_to(репо)):каталог.хэш(x.read_bytes()) for x in файлы}
        результат={'схема':'fum.профиль-каталога-циклов.1','повторы':запуски,'исходники_sha256':хэши,
            'двоичные_sha256':{x:каталог.хэш((двоичные/x).read_bytes()) for x in ('писатель-контейнера','читатель-контейнера')},
            'сегмент_sha256':до,'сегмент_байтов':сегмент.stat().st_size,
            'медианы':{k:int(statistics.median(x['измерения'][k] for x in запуски)) for k in запуски[0]['измерения']},
            'граница':'Git-фикстура, генерация RAW и импорт вне таймеров. Каталог включает перечень, отдельные извлечения и разбор метаданных; вложенные интервалы не складываются. RSS относится к Python-родителю, память Swift и холодный диск неизвестны.',
            'оптимизация':'Дополнительный постоянный кэш и пакетный RAW-читатель не введены: они расширяют контур. Извлекается один объект за раз, RAW не дублируется в каталоге; новые процессы проверяют ту же SHA-связанную историю. Измерения малой фикстуры не доказывают масштабирование полного сегмента.'}
        параметры.выход.write_bytes(каталог.кодировать(результат)+b'\n')
    finally: пример.doCleanups()


if __name__ == '__main__': выполнить()

def загрузить():
    описание = importlib.util.spec_from_file_location('подготовка_кандидата_тест', СУБЪЕКТ)
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    return модуль


def гит(корень, *аргументы):
    среда = {к: в for к, в in os.environ.items() if not к.startswith('GIT_')}
    среда.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull)
    return subprocess.check_output(['git', '--no-optional-locks', '-c', 'core.hooksPath=' + os.devnull,
        '-C', str(корень), *аргументы], env=среда, stderr=subprocess.PIPE)


def полный_снимок(корень):
    результат = {}
    for каталог, папки, файлы in os.walk(корень, followlinks=False):
        for имя in папки + файлы:
            п = Path(каталог) / имя
            ст = п.lstat()
            результат[str(п.relative_to(корень))] = [ст.st_mode, ст.st_ino, ст.st_mtime_ns,
                os.readlink(п) if п.is_symlink() else hashlib.sha256(п.read_bytes()).hexdigest() if п.is_file() else None]
    return результат



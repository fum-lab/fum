        вход = сам.приватный('повтор.json', сам.вход)
        процесс = subprocess.run([sys.executable, '-B', str(Path(писатель.__file__)), 'повтор',
            '--вход', str(вход)], stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
        сам.assertEqual(процесс.returncode, 0, процесс.stderr.decode())
        сам.assertEqual(json.loads(процесс.stdout), результат)
        with сам.assertRaises(ValueError): писатель.читатель.загрузить_ожидания(сам.доверие, корень=сам.корень)
        сам.assertEqual(сам.ф.гит('rev-parse', 'HEAD').strip(), результат['коммит']['коммит'])
        сам.assertEqual(сам.ф.гит('rev-list', '--count', сам.база+'..HEAD').strip(), '1')
        квитанция = Path(сам.о.параметры['квитанция']); сырые = квитанция.read_bytes()
        подмена = json.loads(сырые); подмена['ожидание']['сообщение_sha256'] = '0'*64
        подмена['результат']['сообщение_sha256'] = '0'*64
        квитанция.write_bytes(байты(подмена))
        with patch.object(писатель.коммит, 'восстановить') as восстановление:
            with сам.assertRaises(ValueError): писатель.повтор(сам.вход)
            восстановление.assert_not_called()
        квитанция.unlink()
        with сам.assertRaises(ValueError): писатель.повтор(сам.вход)
        квитанция.write_bytes(сырые); квитанция.chmod(0o600)


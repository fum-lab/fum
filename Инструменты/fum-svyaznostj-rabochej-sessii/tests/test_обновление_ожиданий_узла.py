    def test_реальный_коммит_новое_доверие_повтор_новым_процессом(сам):
        сам.установка(); сам.готовность()
        прежний_создатель = писатель.коммит.создать
        def после_реального_коммита(*аргументы, **настройки):
            прежний_создатель(*аргументы, **настройки)
            raise InterruptedError
        with patch.object(писатель.коммит, 'создать', side_effect=после_реального_коммита):
            with сам.assertRaises(InterruptedError): писатель.зафиксировать(сам.вход, [обычная.база.ЗАПУСК])
        результат = писатель.повтор(сам.вход)
        сам.assertEqual(результат['доверие']['источник']['sha256'], сам.вход['кандидат']['хэш'])

    def test_новая_схема_сверяет_runtime_native_и_подготовку(сам):
        сам.назначить_публикуемую_схему()
        for корень in (str(сам.корень)+os.sep, str(сам.корень)+os.sep+'.'+os.sep, str(сам.каталог)):
            вход = {**сам.вход, 'корень': корень}
            with сам.subTest(корень=корень), сам.assertRaises(ValueError): писатель.план(вход)
        with patch.dict(os.environ, CODEX_THREAD_ID=обычная.база.ЗАДАЧА):
            with сам.assertRaises(ValueError): писатель.план(сам.вход)
        файл = Path(сам.о.параметры['источник_модели']); сырые = файл.read_bytes()
        строки = сырые.splitlines(keepends=True); начало = json.loads(строки[0])
        начало['payload']['cwd'] = str(сам.каталог)
        файл.write_bytes(байты(начало)+b'\n'+b''.join(строки[1:]))
        try:
            with сам.assertRaisesRegex(ValueError, 'нативн|native|cwd'): писатель.план(сам.вход)
        finally: файл.write_bytes(сырые)
        for поле, значение in [('корень', str(сам.каталог)), ('ветка', 'refs/heads/codex/control'),
                ('исполнитель', обычная.база.ЗАДАЧА)]:
            параметры = {**сам.о.параметры, поле: значение}
            вход = {**сам.вход, 'параметры': сам.ссылка_приватная('чужая-подготовка.json', параметры)}
            with сам.subTest(поле=поле), сам.assertRaises(ValueError): писатель.план(вход)


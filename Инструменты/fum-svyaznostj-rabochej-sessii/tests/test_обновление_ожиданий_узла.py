    def сохранить(сам, имя, значение):
        файл = сам.корень / имя
        файл.write_bytes(байты(значение)); сам.ф.гит('add', имя)
        сам.ф.гит('commit', '-qm', 'Подготовить независимую фикстуру')
        return {'коммит': сам.ф.гит('rev-parse', 'HEAD').strip(),
            'путь': имя, 'sha256': писатель.хэш(байты(значение))}


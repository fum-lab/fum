"""Реальный профиль CLI: готовность, первое создание и чтение квитанции."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import statistics
import sys

from test_обычной_дочерней_точки import ОбычнаяДочерняяТочка
import обычное_поручение


def хэши_исходников():
    корень = Path(__file__).resolve().parents[3]
    пути = {Path(__file__).resolve()}
    for модуль in tuple(sys.modules.values()):
        значение = getattr(модуль, '__file__', None)
        if значение:
            путь = Path(значение).resolve()
            if путь.is_relative_to(корень) and путь.suffix == '.py':
                пути.add(путь)
    return {путь.relative_to(корень).as_posix(): hashlib.sha256(путь.read_bytes()).hexdigest()
        for путь in sorted(пути)}


def измерить(повторы):
    исходники = хэши_исходников()
    наблюдения = []
    for _ in range(повторы):
        случай = ОбычнаяДочерняяТочка()
        try:
            случай.setUp()
            профиль = []
            квитанция = случай.выполнить_цикл_команд(профиль)
            наблюдения.append({'внешние_вызовы': профиль, 'стадии_первого_создания': квитанция['профиль'],
                'состояние': квитанция['состояние'], 'процесс': квитанция['процесс'],
                'один_новый_коммит': True, 'квитанция_и_готовность_неизменны_при_повторе': True})
        finally:
            случай.doCleanups()
    assert исходники == хэши_исходников()
    return {'схема': 'fum.профиль-обычной-дочерней-точки.1', 'повторы': повторы,
        'единица': 'наносекунды', 'часы': 'perf_counter_ns', 'python': platform.python_version(),
        'среда': platform.platform(), 'исходники': исходники, 'хэши_неизменны': True,
        'граница': 'Внешние CLI-вызовы измерены отдельно. Подготовка фикстуры, сообщение и проверка данных исключены. '
            'Внутренние стадии вложены в первое создание и повторно не суммируются. '
            'Профиль квитанции относится только к первому созданию; повтор имеет собственный внешний замер. '
            'Это небольшая изолированная фикстура, не рабочий цикл FUM.',
        'наблюдения': наблюдения,
        'медианы_внешних_вызовов': {имя: statistics.median(
            пункт['длительность_наносекунды'] for наблюдение in наблюдения
            for пункт in наблюдение['внешние_вызовы'] if пункт['стадия'] == имя)
            for имя in ('готовность', 'первое создание', 'повторное чтение')}}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--повторы', type=int, default=3)
    разбор.add_argument('--выход', type=Path, required=True)
    параметры = разбор.parse_args()
    if not 1 <= параметры.повторы <= 10:
        разбор.error('число повторов должно быть от 1 до 10')
    данные = измерить(параметры.повторы)
    with параметры.выход.open('x') as поток:
        поток.write(json.dumps(данные, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'повторы': данные['повторы'], 'медианы_нс': данные['медианы_внешних_вызовов']}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

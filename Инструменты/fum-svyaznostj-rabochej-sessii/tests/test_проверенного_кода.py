def байты_манифеста(объект):
    return json.dumps(объект, ensure_ascii=False, sort_keys=True).encode()


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


class Фикстура:
    def __init__(сам, число=2):
        сам.временное = tempfile.TemporaryDirectory(prefix="fum-checked-")
        сам.корень = Path(сам.временное.name)
        сам.пакет = сам.корень / "контур"
        сам.пакет.mkdir()
        for путь in (СКРИПТЫ / "проверенный_код").glob("*.py"):
            (сам.пакет / путь.name).write_bytes(путь.read_bytes())
        сам.записать("модуль.py", "значение = 'Q:кириллица'\r\n")
        сам.записать("отложенный.py", "значение = 73\n")
        сам.записать("программа.py", "from . import модуль\nзначение = модуль.значение\n"
            "def позже():\n    from . import отложенный\n    return отложенный.значение\n"
            "def неизвестный():\n    from . import скрытый\n    return скрытый.значение\n"
            "def ошибка():\n    raise RuntimeError('ошибка программы')\n")
        сам.записать("под/__init__.py", "\n")
        сам.записать("под/элемент.py", "значение = 19\n")
        for номер in range(число):
            сам.записать(f"набор{номер}.py", f"значение = {номер}\n")
        сам.гит("init", "-q")
        сам.зафиксировать()

    def записать(сам, имя, текст):
        путь = сам.пакет / имя
        путь.parent.mkdir(parents=True, exist_ok=True)
        путь.write_bytes(текст.encode())

    def гит(сам, *аргументы):
        среда = os.environ.copy()
        среда.update(GIT_AUTHOR_NAME="Открытая фикстура", GIT_AUTHOR_EMAIL="fixture@example.invalid",
            GIT_COMMITTER_NAME="Открытая фикстура", GIT_COMMITTER_EMAIL="fixture@example.invalid",
            GIT_AUTHOR_DATE="2026-10-09T00:00:00Z", GIT_COMMITTER_DATE="2026-10-09T00:00:00Z")
        return subprocess.check_output(["git", "-C", str(сам.корень), *аргументы], env=среда)

    def зафиксировать(сам):
        сам.гит("add", "--", "контур")
        сам.гит("commit", "-qm", "Открытый набор")
        сам.коммит = сам.гит("rev-parse", "HEAD").decode().strip()
        модули = []
        for строка in сам.гит("ls-tree", "-rz", "--full-tree", сам.коммит, "--", "контур").split(b"\0"):
            if not строка:
                continue
            мета, путь = строка.split(b"\t", 1)
            режим, вид, объект_гита = мета.decode().split()
            путь = путь.decode()
            имя = путь[:-3].replace("/", ".") if путь.endswith(".py") else путь.replace("/", ".")
            if имя.endswith(".__init__"):
                имя = имя[:-9]
            данные = сам.гит("cat-file", "blob", объект_гита)
            модули.append({"имя": имя, "путь": путь, "режим": режим, "blob": объект_гита, "sha256": хэш(данные)})
        сам.манифест = {"схема": "fum.проверенный-код.1", "пространство": "контур",
            "каталог": "контур", "модули": модули}
        начало = next(э for э in модули if э["путь"] == "контур/начало.py")
        сам.закрепление = {"коммит": сам.коммит, "начало": {к: начало[к] for к in ("путь", "режим", "blob", "sha256")},
            "манифест_sha256": хэш(байты_манифеста(сам.манифест))}

    def снимок(сам, манифест=None, закрепление=None, перепривязать=False):
        данные = байты_манифеста(сам.манифест if манифест is None else манифест)
        закрепления = copy.deepcopy(сам.закрепление if закрепление is None else закрепление)
        if перепривязать:
            закрепления["манифест_sha256"] = хэш(данные)
        return получить_снимок(сам.корень, закрепления, данные)

    def закрыть(сам):
        сам.временное.cleanup()



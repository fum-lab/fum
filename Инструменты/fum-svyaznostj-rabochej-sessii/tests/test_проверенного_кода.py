    def test_полное_восстановление_модулей_и_поиска(сам):
        снимок = сам.набор.снимок()
        старый = types.ModuleType("контур"); старый.__path__ = [str(сам.набор.пакет)]
        дочерний = types.ModuleType("контур.под"); дочерний.__path__ = старый.__path__
        старый.под = дочерний
        скрытый = types.ModuleType("контур.скрытый"); скрытый.значение = "W"
        сосед = types.ModuleType("контур2")
        прежние = {"контур": старый, "контур.под": дочерний, "контур.скрытый": скрытый, "контур.пустой": None}
        sys.modules.update(прежние); sys.modules["контур2"] = сосед
        сам.addCleanup(sys.modules.pop, "контур2", None)
        поиск = tuple(sys.meta_path)
        for исключение in (False, True):
            try:
                with снимок.исполнение() as сеанс:
                    модуль = сеанс.загрузить("контур.программа")
                    сам.assertEqual(модуль.значение, "Q:кириллица")
                    сам.assertEqual(сеанс.загрузить("контур.под.элемент").значение, 19)
                    with сам.assertRaises(ImportError):
                        модуль.неизвестный()
                    with сам.assertRaises(ModuleNotFoundError):
                        сеанс.загрузить("контур.скрытый")
                    if исключение:
                        модуль.ошибка()
            except RuntimeError:
                сам.assertTrue(исключение)
            сам.assertEqual(tuple(sys.meta_path), поиск)
            фактические = {к: в for к, в in sys.modules.items() if к == "контур" or к.startswith("контур.")}
            сам.assertEqual(set(фактические), set(прежние))
            for ключ in прежние:
                сам.assertIs(фактические[ключ], прежние[ключ])
            сам.assertIs(sys.modules["контур2"], сосед)


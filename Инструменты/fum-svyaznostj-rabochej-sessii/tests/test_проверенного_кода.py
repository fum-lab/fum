    def test_отказ_входа_восстанавливает_старые_объекты(сам):
        def отказ(получатель, индекс, значение):
            list.insert(получатель, индекс, значение)
            raise RuntimeError("отказ установки finder после вставки")
        ПлохойПоиск = type("ПлохойПоиск", (list,), {"insert": отказ})
        снимок = сам.набор.снимок()
        прежний = types.ModuleType("контур")
        sys.modules["контур"] = прежний
        поиск = sys.meta_path
        setattr(sys, "meta_path", ПлохойПоиск(поиск))
        try:
            with сам.assertRaises(RuntimeError):
                with снимок.исполнение():
                    pass
            сам.assertIs(sys.modules["контур"], прежний)
            сам.assertEqual(sys.meta_path, поиск)
        finally:
            setattr(sys, "meta_path", поиск)
        with снимок.исполнение() as сеанс:
            сам.assertEqual(сеанс.загрузить("контур.модуль").значение, "Q:кириллица")



"""Профиль одного свежего процесса; вызывающая сторона запускает три процесса."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import statistics
import sys
import time
import tracemalloc

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_классификации_продолжения_модели as примеры


def сценарии():
    пара = ('gpt-6.1-sol', 'ultra')
    начало = примеры.сырой_снимок((пара,))
    строка = примеры.строка({'type': 'event_msg', 'payload': {'text': 'x' * 1024}})
    большой = начало + строка * 1024 + примеры.строка({'type': 'turn_context',
        'timestamp': '2026-10-14T10:01:00Z', 'payload': {'model': пара[0], 'effort': пара[1]}})
    смены = примеры.сырой_снимок(tuple(
        пара if номер % 2 == 0 else ('gpt-6-astra', 'high') for номер in range(2000)))
    исходная = примеры.полная_история(начало)
    результаты = {'малый': (примеры.входы((пара, пара, пара)), 'добавлены_наблюдения_той_же_пары')}
    for имя, сырые, диагноз in (('немодельные_строки', большой, 'добавлены_наблюдения_той_же_пары'),
            ('много_переключений', смены, 'наблюдаемое_переключение')):
        текущая = примеры.полная_история(сырые)
        результаты[имя] = ((исходная, текущая, примеры.подтверждение(исходная, текущая, сырые)), диагноз)
    return результаты


def отпечаток_входа(данные):
    исходная, текущая, подтверждение = данные
    хэш = hashlib.sha256()
    for часть in (примеры.байты_истории(исходная), примеры.байты_истории(текущая),
            подтверждение['сырые_байты_снимка'], примеры.байты_истории({
                к: в for к, в in подтверждение.items() if к != 'сырые_байты_снимка'})):
        хэш.update(len(часть).to_bytes(8, 'big')); хэш.update(часть)
    return хэш.hexdigest()


def код():
    каталог = Path(__file__).resolve().parents[1]
    пути = [каталог / 'scripts' / имя for имя in ('классификация_продолжения_модели.py',
        'история_модели.py', 'сообщения_задачи.py', 'автор_коммита.py')]
    пути.extend((Path(__file__).resolve(), Path(примеры.__file__).resolve()))
    return {п.relative_to(каталог).as_posix(): hashlib.sha256(п.read_bytes()).hexdigest() for п in пути}


def измерить(данные, диагноз, повторы):
    исходный_хэш = отпечаток_входа(данные)
    длительности, пики, стадии = [], [], {}
    выбранные = {'_хэш_истории', '_хэш_префикса', '_восстановить_историю'}
    активные = {}
    def метка(кадр, событие, аргумент):
        if кадр.f_globals.get('__name__') != 'классификация_продолжения_модели' or кадр.f_code.co_name not in выбранные:
            return
        имя = кадр.f_code.co_name
        if событие == 'call': активные[id(кадр)] = time.perf_counter_ns()
        elif событие == 'return':
            начало = активные.pop(id(кадр))
            стадии.setdefault(имя, []).append(time.perf_counter_ns() - начало)
    for _ in range(повторы):
        tracemalloc.start()
        sys.setprofile(метка)
        начало = time.perf_counter_ns()
        try:
            ответ = примеры.классификация.классифицировать_продолжение(*данные)
            длительности.append(time.perf_counter_ns() - начало)
            пики.append(tracemalloc.get_traced_memory()[1])
        finally:
            sys.setprofile(None); tracemalloc.stop()
        assert ответ['диагноз'] == диагноз
    assert not активные and отпечаток_входа(данные) == исходный_хэш
    return {'вход_sha256': исходный_хэш, 'диагноз': диагноз,
        'сырых_байтов': len(данные[2]['сырые_байты_снимка']),
        'длительности_нс': длительности, 'медиана_нс': statistics.median(длительности),
        'пики_памяти_байты': пики, 'стадии_нс': стадии}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--повторов', type=int, default=3)
    разбор.add_argument('--выход')
    параметры = разбор.parse_args()
    if параметры.повторов <= 0: разбор.error('нужно положительное число повторов')
    до = код()
    входы = сценарии()
    результаты = {имя: измерить(данные, диагноз, параметры.повторов)
        for имя, (данные, диагноз) in входы.items()}
    assert код() == до
    итог = {'схема': 'fum.профиль-классификации-продолжения-модели.1',
        'идентификатор_процесса': os.getpid(), 'версия_интерпретатора': sys.version, 'исходники_sha256': до,
        'сценарии': результаты, 'входы_неизменны': True,
        'граница': 'Подготовка исключена; общий вызов включает профильные метки и tracemalloc. Вложенные стадии не складываются с общим временем. Кэш ОС не очищается.'}
    сырые = (json.dumps(итог, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()
    if параметры.выход:
        with os.fdopen(os.open(параметры.выход, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600), 'wb') as поток:
            поток.write(сырые); поток.flush(); os.fsync(поток.fileno())
    sys.stdout.buffer.write(сырые)


if __name__ == '__main__':
    главная()

КОРЕНЬ = Path(__file__).resolve().parents[3]


def хэш_файла(путь):
    return hashlib.sha256(путь.read_bytes()).hexdigest()


def загруженные_пути():
    очередь = [м for м in tuple(sys.modules.values()) if isinstance(м, ModuleType)]
    посещённые = set(); пути = {Path(__file__).resolve()}
    while очередь:
        модуль = очередь.pop()
        if id(модуль) in посещённые: continue
        посещённые.add(id(модуль))
        имя = getattr(модуль, '__file__', None)
        if имя:
            путь = Path(имя).resolve()
            if путь.is_relative_to(КОРЕНЬ) and путь.suffix == '.py':
                пути.add(путь)
                очередь.extend(м for м in vars(модуль).values() if isinstance(м, ModuleType))
    return пути


def измерить():
    # Консервативный снимок до lazy imports; результат содержит только реально загруженные/вызванные пути.
    имена = subprocess.check_output(['git', '-C', str(КОРЕНЬ), 'ls-files', '--cached', '--others',
        '--exclude-standard', '-z', '--', 'Инструменты/**/*.py'],
        env={**__import__('os').environ, 'GIT_OPTIONAL_LOCKS': '0'}).split(b'\0')
    до = {КОРЕНЬ / имя.decode(): хэш_файла(КОРЕНЬ / имя.decode()) for имя in имена if имя}
    наблюдения = []; трасса = cProfile.Profile()
    for слияние in (False, True):
        ф = база.СозданиеКоммита()
        try:
            ф.setUp()
            if слияние:
                ф.гит('checkout', '-qb', 'codex/источник'); (ф.корень / 'вклад.txt').write_text('вклад\n')
                ф.гит('add', 'вклад.txt'); ф.гит('commit', '-qm', 'Вклад'); второй = ф.гит('rev-parse', 'HEAD').strip()
                ф.гит('checkout', '-q', 'codex/фикстура'); ф.гит('merge', '--no-ff', '--no-commit', второй)
                ф.параметры['родители'].append(второй); ф.параметры['разрешённые_цели'].append('вклад.txt')
                ф.запрос.write_text(ф.запрос.read_text() + '- [Вклад](../../вклад.txt).\n')
            ф.готовить(False)
            вход = фасад.ВходКонтрольнойТочки.из_значений(ф.параметры['подготовка'], [база.ЗАПУСК])
            условия = {'исходник_байтов': ф.источник.stat().st_size, 'исходник_sha256': хэш_файла(ф.источник),
                'курсор_до_sha256': хэш_файла(Path(ф.параметры['кэш_модели'])),
                'готовность_до': база.коммит.готовность.путь_этапа(ф.параметры).exists(), 'родителей': len(ф.параметры['родители'])}
            шаги = []
            def замер(имя, действие, *, отказ=False):
                читатели = []; ранние = []; эффекты = []
                def обёртка(имя, функция):
                    def читать(*аргументы, **именованные_аргументы):
                        начало = time.perf_counter_ns(); результат = None
                        try:
                            результат = функция(*аргументы, **именованные_аргументы); return результат
                        finally:
                            читатели.append({'читатель': имя, 'длительность_наносекунды': time.perf_counter_ns()-начало,
                                'профиль': None if результат is None else результат['профиль']})
                    return читать
                def ранний_вызов(*аргументы, **именованные_аргументы):
                    начало = time.perf_counter_ns()
                    try: return оригинальный_допуск(*аргументы, **именованные_аргументы)
                    finally: ранние.append(time.perf_counter_ns()-начало)
                оригинальный_допуск = фасад.ранний_допуск
                исходный_гит = база.коммит.гит
                def гит(корень, *аргументы, **именованные_аргументы):
                    if аргументы and аргументы[0] == 'commit': эффекты.append('commit')
                    return исходный_гит(корень, *аргументы, **именованные_аргументы)
                with mock.patch.object(база.коммит.сообщения, 'прочитать_сообщения',
                        side_effect=обёртка('команды', база.коммит.сообщения.прочитать_сообщения)), \
                     mock.patch.object(база.коммит.модели, 'импортировать',
                        side_effect=обёртка('модель', база.коммит.модели.импортировать)), \
                     mock.patch.object(фасад, 'ранний_допуск', side_effect=ранний_вызов), \
                     mock.patch.object(база.коммит, 'гит', side_effect=гит):
                    начало = time.perf_counter_ns(); отклонён = False
                    try: итог = трасса.runcall(действие)
                    except база.коммит.ОшибкаКоммита:
                        if not отказ: raise
                        отклонён = True; итог = None
                    if отказ and not отклонён: raise AssertionError('нет ожидаемого отказа')
                    шаги.append({'стадия': имя, 'длительность_наносекунды': time.perf_counter_ns()-начало,
                        'вызовы_git_commit': len(эффекты), 'исход': 'отказ' if отклонён else 'успех', 'ранний_допуск_наносекунды': ранние,
                        'число_вызовов': {имя: sum(ч['читатель']==имя for ч in читатели) for имя in ('команды','модель')},
                        'прочитано_байтов': sum(ч['профиль']['прочитано_байтов'] for ч in читатели)
                            if all(ч['профиль'] is not None for ч in читатели) else None,
                        'читатели': читатели})
                    return итог
            замер('неверный JSON-путь вместо UUID', lambda: база.коммит.объявить_готовность(
                Path(ф.параметры['подготовка']), [str(ф.источник)], 600), отказ=True)
            assert шаги[-1]['число_вызовов'] == {'команды': 0, 'модель': 0}
            готовность = замер('готовность: ранний и полный допуск', lambda: вход.готово(600))
            эпоха = готовность['готов_в_наносекундах_эпохи']
            первый = замер('первое создание: полный допуск', вход.создать)
            квитанция = Path(ф.параметры['квитанция']); состояние = Path(готовность['путь'])
            сохранённые = (квитанция.read_bytes(), состояние.read_bytes())
            второй = замер('повтор: чтение успешной квитанции', вход.создать)
            assert первый == второй and сохранённые == (квитанция.read_bytes(), состояние.read_bytes())
            assert база.коммит.готовность.прочитать(состояние)['готов_в_наносекундах_эпохи'] == эпоха
            assert ф.гит('rev-list', '--count', ф.начало + '..HEAD').strip() == ('2' if слияние else '1')
            assert sum(ш['вызовы_git_commit'] for ш in шаги) == 1
            наблюдения.append({'сценарий': 'merge' if слияние else 'обычная точка', 'условия': условия,
                'внешние_вызовы': шаги, 'стадии_создателя': json.loads(сохранённые[0])['профиль'],
                'один_вызов_создания_коммита': True, 'эпоха_готовности_сохранена': True, 'повтор_неизменен': True})
        finally:
            ф.doCleanups()
    пути = загруженные_пути()
    for запись in трасса.getstats():
        if hasattr(запись.code, 'co_filename'):
            путь = Path(запись.code.co_filename).resolve()
            if путь.is_relative_to(КОРЕНЬ) and путь.suffix == '.py': пути.add(путь)
    все = all(путь in до and до[путь] == хэш_файла(путь) for путь in пути)
    assert все
    return {'схема': 'fum.профиль-типизированной-контрольной-точки.1',
        'часы': 'perf_counter_ns', 'python': platform.python_version(), 'среда': platform.platform(),
        'git': subprocess.check_output(['git', '--version'], text=True).strip(),
        'исходники': {п.relative_to(КОРЕНЬ).as_posix(): до[п] for п in sorted(пути)},
        'хэши_до_и_после_совпали': все, 'наблюдения': наблюдения,
        'граница': 'Время инструментированных вызовов включает cProfile и делегирующие обёртки. Подготовка фикстур и запуск v4 исключены. Ранний gate, reader и стадии создателя вложены '
            'во внешние вызовы и не суммируются. Байты — реальные счётчики native readers, не физическое дисковое I/O. '
            'Неуспешное чтение без профиля имеет неизвестное число байтов. Манифест охватывает фактически '
            'загруженные и вызванные Python-файлы текущего checkout малого профиля; это не перенос GREEN и не ускорение всего FUM.'}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path, required=True)
    п = разбор.parse_args(); данные = измерить()
    with п.выход.open('x', encoding='utf-8') as поток:
        поток.write(json.dumps(данные, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'сценариев': len(данные['наблюдения']), 'исходников': len(данные['исходники'])}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

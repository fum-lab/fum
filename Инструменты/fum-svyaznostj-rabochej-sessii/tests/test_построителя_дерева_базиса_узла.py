    def успешный(сам, ожидаемые=None):
        пример = сам.пример
        ожидаемые = пример.ожидаемые() if ожидаемые is None else ожидаемые
        идентификатор = ожидаемое_дерево(пример.корень, ожидаемые, пример.эталонные_объекты)
        результат = сам.вызвать()
        сам.assertEqual(результат['дерево'], идентификатор)
        сам.assertTrue((пример.объекты / идентификатор[:2] / идентификатор[2:]).is_file())
        сам.assertEqual(результат['родители'], [пример.вход['K'], пример.вход['R']])
        сырые = штатный_гит(пример.корень, 'ls-tree', '-r', '-z', идентификатор, объекты=пример.объекты)
        фактические = {}
        for строка in сырые.split(b'\0'):
            if строка:
                мета, имя = строка.split(b'\t', 1)
                фактические[имя.decode()] = tuple(мета.decode().split(' '))
        сам.assertEqual(фактические, ожидаемые)
        сам.assertEqual(результат['защищённые'], пример.ф.защищённые())
        for префикс in пример.объекты.iterdir():
            for путь in префикс.iterdir():
                сам.assertEqual(штатный_гит(пример.корень, 'cat-file', '-t', префикс.name + путь.name,
                    объекты=пример.объекты).strip(), b'tree')
        return результат


def штатный_гит(корень, *аргументы, ввод=None, объекты=None):
    среда = базис.среда_гит()
    if объекты is not None:
        среда['GIT_OBJECT_DIRECTORY'] = str(объекты)
        исходные = Path(базис.гит(корень, 'rev-parse', '--git-path', 'objects').decode().strip())
        среда['GIT_ALTERNATE_OBJECT_DIRECTORIES'] = str((исходные if исходные.is_absolute()
            else корень / исходные).resolve())
    процесс = subprocess.run(['git', '--no-optional-locks', '--no-replace-objects',
        '-c', 'core.hooksPath=' + os.devnull, '-C', str(корень), *аргументы],
        input=ввод, capture_output=True, env=среда, timeout=30)
    if процесс.returncode:
        raise AssertionError(процесс.stderr.decode())
    return процесс.stdout


def ожидаемое_дерево(корень, листья, объекты):
    """Oracle использует только вручную выбранные листья и штатный mktree."""
    узел = {}
    for путь, запись in листья.items():
        ныне = узел
        части = путь.split('/')
        for часть in части[:-1]:
            ныне = ныне.setdefault(часть, {})
        ныне[части[-1]] = запись
    def записать(ветвь):
        строки = []
        for имя, значение in ветвь.items():
            режим, тип, идентификатор = ('040000', 'tree', записать(значение)) if isinstance(значение, dict) else значение
            строки.append((режим + ' ' + тип + ' ' + идентификатор + '\t' + имя).encode() + b'\0')
        return штатный_гит(корень, 'mktree', '-z', '--missing', ввод=b''.join(строки), объекты=объекты).decode().strip()
    return записать(узел)


def снимок(корень):
    """Включая source ODB, refs, конфигурацию, индекс и буквальные ссылки."""
    итог = {}
    for каталог, подкаталоги, файлы in os.walk(корень, followlinks=False):
        for имя in [*подкаталоги, *файлы]:
            путь = Path(каталог) / имя
            состояние = путь.lstat()
            содержимое = os.readlink(путь) if stat.S_ISLNK(состояние.st_mode) else (
                hashlib.sha256(путь.read_bytes()).hexdigest() if путь.is_file() else None)
            итог[str(путь.relative_to(корень))] = (stat.S_IFMT(состояние.st_mode), stat.S_IMODE(состояние.st_mode), содержимое)
    return итог


class ПримерПостроителя:
    def __init__(сам, каталог):
        сам.каталог = Path(каталог).resolve()
        сам.ф = ПримерПервогоЦикла(сам.каталог)
        сам.корень = сам.ф.корень

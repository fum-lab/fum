"""Раздельные интервалы лабораторной подготовки, эффекта и чтения успеха."""
import hashlib
import json
import time

from test_принимающего_фасада import ПринимающийФасад
from принимающий_фасад_обратного_приёма import восстановить


def измерить():
    опыт = ПринимающийФасад()
    опыт.setUp()
    try:
        начало = time.perf_counter_ns()
        основание = опыт.подготовить()
        подготовка = time.perf_counter_ns() - начало
        начало = time.perf_counter_ns()
        результат = опыт.применить(основание)
        эффект = time.perf_counter_ns() - начало
        файлы = {п.name: п.read_bytes() for п in опыт.каталог.iterdir()}
        количество = опыт.гит("rev-list", "--count", "HEAD")
        начало = time.perf_counter_ns()
        восстановленное = восстановить(основание.свидетельство,
            hashlib.sha256(основание.свидетельство).hexdigest(), допуск_получателя=опыт.допуск)
        повтор = опыт.применить(восстановленное, повтор=True)
        чтение = time.perf_counter_ns() - начало
        assert повтор == результат
        assert файлы == {п.name: п.read_bytes() for п in опыт.каталог.iterdir()}
        assert опыт.гит("rev-list", "--count", "HEAD") == количество
        assert опыт.счётчик.read_text() == "1"
        return {"схема": "fum.профиль-принимающего-фасада.1", "опытов": 1,
            "подготовка_нс": подготовка, "первичный_эффект_нс": эффект,
            "восстановление_и_повтор_нс": чтение, "новых_коммитов": 1,
            "предметных_запусков": 1, "повтор_без_записи": True,
            "граница": "Малая локальная Git-фикстура, синтетический ROOT-допуск. "
                "Подготовка фикстуры и единственный тест кандидата вне интервалов. "
                "Восстановление в том же процессе; свежий процесс проверяет отдельная регрессия. "
                "Ускорение производственной интеграции FUM не измерено."}
    finally:
        опыт.doCleanups()


if __name__ == "__main__":
    print(json.dumps(измерить(), ensure_ascii=False, sort_keys=True))

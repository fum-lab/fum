"""Парный профиль штатной композиции и CLI на одних готовых ROOT .5-байтах."""
import sys
sys.dont_write_bytecode = True
import os
import json
import subprocess
from pathlib import Path


def отказ(причина):
    sys.stderr.write(json.dumps({'схема': 'fum.отказ-профиля-сверки.1', 'причина': причина}, ensure_ascii=False)+'\n')
    return 2


def назначение(значение):
    путь = Path(значение)
    if not путь.is_absolute() or путь.as_posix()!=значение or путь.parent.resolve()!=путь.parent:
        raise ValueError('нужен физический абсолютный новый выход')
    if any(п.is_symlink() for п in [путь, *путь.parents]) or os.path.lexists(путь):
        raise ValueError('выход занят либо содержит symlink')
    if any(os.path.lexists(п / '.git') for п in путь.parents):
        raise ValueError('выход должен находиться вне Git')
    с = путь.parent.stat()
    if с.st_uid!=os.getuid() or с.st_mode & 0o777 != 0o700:
        raise ValueError('нужен собственный каталог0700')
    return путь


def установить(путь, данные):
    назначение(str(путь))
    дескриптор = os.open(путь, os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'wb') as поток:
        поток.write(данные); поток.flush(); os.fsync(поток.fileno())


def замыкание(проверки, модуль):
    результат = {}
    загруженные = [*sys.modules.values(), модуль.штатный.сообщения._КЛАССИФИКАТОР]
    for загруженный in загруженные:
        имя = getattr(загруженный, '__file__', None)
        if имя and Path(имя).is_relative_to(проверки.КОРЕНЬ):
            файл = Path(имя)
            if файл.is_file(): результат[str(файл.relative_to(проверки.КОРЕНЬ))] = проверки.хэш(файл.read_bytes())
    return результат


def штатное_чтение(ф, модуль, выбранный_хэш, счётчики=None):
    """Ручная композиция stock API с теми же guard на этих обычных файлах."""
    снимки = модуль.чтение.Снимки()
    до = подмена = None; проверено = False
    def гит(корень, *аргументы):
        б = модуль.прочитать_гит(корень, *аргументы)
        if счётчики is not None:
            счётчики['гит_вызовов'] = счётчики.get('гит_вызовов', 0)+1
            счётчики['гит_байтов'] = счётчики.get('гит_байтов', 0)+len(б)
        return б
    def состояние():
        if гит(ф.корень, 'rev-parse', '--show-toplevel').decode().strip()!=str(ф.корень):
            raise ValueError('другой физический корень Git')
        if гит(ф.корень, 'symbolic-ref', 'HEAD').decode().strip()!=ф.выбор['ветка'] \
            or гит(ф.корень, 'rev-parse', 'HEAD').decode().strip()!=ф.итог['коммит']:
            raise ValueError('HEAD/ref изменились')
    try:
        сырые = снимки.читать(str(модуль.приватный(str(ф.вход))), приватный=True)
        if модуль.чтение.хэш(сырые)!=выбранный_хэш: raise ValueError('SHA выбора')
        выбор = модуль.чтение.разобрать(сырые)
        модуль.проверить_выбор(выбор)
        данные = {}; исходные = {}
        for имя, запись in выбор['файлы'].items():
            б = снимки.читать(запись['путь'], приватный=True)
            if модуль.чтение.хэш(б)!=запись['sha256']: raise ValueError('дрейф комплекта')
            исходные[имя] = б; данные[имя] = модуль.чтение.разобрать(б)
        п = модуль.контракт(выбор, данные['подготовка'], данные['квитанция'], исходные['подготовка'])
        модуль.чтение.физический(выбор['корень']); проверено = True
        состояние()
        индекс = Path(гит(ф.корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index').decode().strip())
        снимки.читать(str(индекс), предел=индекс.stat().st_size)
        подмена = Path(гит(ф.корень, 'rev-parse', '--path-format=absolute', '--git-path', 'info/grafts').decode().strip())
        if os.path.lexists(подмена): raise ValueError('grafts')
        объект = модуль.перепривязать(модуль.штатный.проверить_объект, гит=гит)
        восстановить = модуль.перепривязать(модуль.штатный.восстановить, гит=гит, проверить_объект=объект)
        результат = восстановить(ф.корень, данные['квитанция'], Path(ф.параметры['квитанция']))
        до = гит(ф.корень, 'ls-files', '--stage', '-v', '-z')
        for запись in до.split(b'\0'):
            if not запись: continue
            сведения, имя = запись.split(b'\t', 1)
            if сведения.decode().split()[1] not in ('100644', '100755'):
                raise ValueError('профиль выбран только для обычных файлов фикстуры')
            файл = ф.корень / os.fsdecode(имя); снимки.читать(str(файл), предел=файл.stat().st_size)
        индексный = модуль.перепривязать(модуль.штатный.индекс, гит=гит)
        if индексный(ф.корень)!=данные['квитанция']['индекс_sha256']: raise ValueError('индекс')
        if гит(ф.корень, 'diff-index', '--cached', '--name-only', '-z', ф.итог['коммит']): raise ValueError('индекс/C')
        имена = гит(ф.корень, 'diff-tree', '--no-commit-id', '--name-only', '--no-renames', '-r', '-z',
            п['родители'][0], ф.итог['коммит']).split(b'\0')
        if any(os.fsdecode(и) not in п['разрешённые_цели'] for и in имена if и): raise ValueError('состав')
    finally:
        ошибки = []
        try:
            try:
                try:
                    if проверено:
                        if до is not None and до!=гит(ф.корень, 'ls-files', '--stage', '-v', '-z'): raise ValueError('индекс изменился')
                        if подмена is not None and os.path.lexists(подмена): raise ValueError('grafts появились')
                except (ValueError, OSError, subprocess.SubprocessError) as ошибка: ошибки.append(str(ошибка))
            finally:
                try:
                    try: модуль.проверить_наблюдения([], гит, подмена)
                    except (ValueError, OSError, subprocess.SubprocessError) as ошибка: ошибки.append(str(ошибка))
                finally:
                    try:
                        try: модуль.проверить_снимки(снимки)
                        except (ValueError, OSError) as ошибка: ошибки.append(str(ошибка))
                    finally:
                        if проверено:
                            try: состояние()
                            except (ValueError, OSError, subprocess.SubprocessError) as ошибка: ошибки.append(str(ошибка))
        finally:
            try:
                try: модуль.проверить_наблюдения([], гит, подмена)
                except (ValueError, OSError, subprocess.SubprocessError) as ошибка: ошибки.append(str(ошибка))
            finally:
                try: модуль.закрыть_снимки(снимки)
                except (ValueError, OSError) as ошибка: ошибки.append(str(ошибка))
            if счётчики is not None: счётчики['прочитано_файловых_байтов'] = снимки.прочитано
            if ошибки: raise ValueError('; '.join(ошибки))
    return {'схема': 'fum.результат-читающей-сверки.1', 'результат': результат, 'публикация': None}


def поздние_отказы(ф, модуль, проверки, выбранный_хэш):
    """Инъекции и наблюдение отказов целиком вне чистого таймера."""
    другая = 'refs/heads/codex/другая'; ф.гит('update-ref', другая, ф.итог['коммит'])
    оригинал = Path(ф.параметры['подготовка']).read_bytes(); итоги = {}
    подмена = Path(модуль.прочитать_гит(ф.корень, 'rev-parse', '--path-format=absolute', '--git-path', 'info/grafts').decode().strip())
    for вид in ('реф', 'байты_до_сверки_файлов', 'байты', 'grafts'):
        отказы = []
        for вариант in ('A', 'B'):
            исходный = модуль.прочитать_гит; число_индексов = число_корней = 0; сработало = False
            def чтение(корень, *аргументы):
                nonlocal число_индексов, число_корней, сработало
                ответ = исходный(корень, *аргументы)
                if аргументы==('ls-files', '--stage', '-v', '-z'): число_индексов += 1
                if аргументы==('rev-parse', '--show-toplevel'): число_корней += 1
                if вид=='реф' and число_индексов==4 and аргументы==('ls-files', '--stage', '-v', '-z'):
                    ф.гит('symbolic-ref', 'HEAD', другая); сработало = True
                if вид=='байты_до_сверки_файлов' and число_индексов==4 and аргументы==('ls-files', '--stage', '-v', '-z'):
                    with Path(ф.параметры['подготовка']).open('ab') as поток: поток.write(b' ')
                    сработало = True
                if вид=='байты' and число_корней==2 and аргументы==('rev-parse', 'HEAD'):
                    with Path(ф.параметры['подготовка']).open('ab') as поток: поток.write(b' ')
                    сработало = True
                if вид=='grafts' and число_корней==2 and аргументы==('rev-parse', 'HEAD'):
                    подмена.parent.mkdir(exist_ok=True); подмена.write_bytes(b''); сработало = True
                return ответ
            try:
                with проверки.mock.patch.object(модуль, 'прочитать_гит', side_effect=чтение):
                    try:
                        if вариант=='A': штатное_чтение(ф, модуль, выбранный_хэш)
                        else: модуль.сверить(ф.вход, выбранный_хэш)
                    except ValueError as ошибка: отказы.append({'тип': type(ошибка).__name__, 'причина': str(ошибка)})
                    else: raise ValueError('поздний дрейф не обнаружен: '+вариант)
                if not сработало: raise ValueError('инъекция не сработала')
            finally:
                ф.гит('symbolic-ref', 'HEAD', ф.выбор['ветка'])
                Path(ф.параметры['подготовка']).write_bytes(оригинал)
                подмена.unlink(missing_ok=True)
        if len(отказы)!=2 or отказы[0]!=отказы[1]: raise ValueError('неравные поздние отказы')
        итоги[вид] = отказы[0]
    return итоги


def главная():
    # Отказ до загрузки helper, подготовка, Git, таймера и открытия выхода.
    if sys.flags.optimize or os.environ.get('PYTHONOPTIMIZE') not in (None, '', '0'):
        return отказ('оптимизация Python запрещена для профиля')
    try:
        import argparse
        разбор = argparse.ArgumentParser(allow_abbrev=False)
        разбор.add_argument('--выход', required=True)
        п = разбор.parse_args(); выход = назначение(п.выход)
        import time
        import statistics
        import unittest
        начало_импорта = time.perf_counter_ns()
        import test_сверки_контрольной_точки as проверки
        модуль = проверки.загрузить()
        профиль = {'схема': 'fum.профиль-читающей-сверки.1', 'граница':
            'Setup и импорты вне чистых таймеров. A — ручная композиция stock читающих API; '
            'B — новый API. Одни обычные файлы, полное равенство шести полей. '
            'Холодный процесс и bare readback измеряются отдельно; весь рабочий цикл неизвестен.',
            'сценарии': [], 'замыкание': {}, 'импорты_наносекунды': time.perf_counter_ns()-начало_импорта}
        for слияние in (False, True):
            владелец = unittest.TestCase(); начало = time.perf_counter_ns()
            try:
                ф = проверки.фикстура(владелец, слияние=слияние)
                подготовка = time.perf_counter_ns()-начало
                коды = замыкание(проверки, модуль)
                for имя, хэш in профиль['замыкание'].items():
                    if коды.get(имя)!=хэш: raise ValueError('дрейф замыкания')
                профиль['замыкание'].update(коды)
                до = проверки.снимок(ф.каталог); измерения = []
                выбранный_хэш = проверки.хэш(ф.вход.read_bytes())
                эталон = {'схема': 'fum.результат-читающей-сверки.1', 'результат': ф.итог, 'публикация': None}
                for раунд, порядок in enumerate(('ABBA', 'BAAB', 'ABBA', 'BAAB'), 1):
                    for вариант in порядок:
                        начало = time.perf_counter_ns()
                        результат = штатное_чтение(ф, модуль, выбранный_хэш) if вариант=='A' else модуль.сверить(ф.вход, выбранный_хэш)
                        длительность = time.perf_counter_ns()-начало
                        if результат!=эталон: raise ValueError('неравный полный результат')
                        измерения.append({'раунд': раунд, 'вариант': вариант, 'наносекунды': длительность, 'исход': 'успех'})
                if проверки.снимок(ф.каталог)!=до: raise ValueError('чистый профиль записал входы')
                # Счётчики отдельного диагностического чтения не замедляют чистый таймер.
                диагностика = {}
                for вариант in ('A', 'B'):
                    счётчики = {}
                    результат = штатное_чтение(ф, модуль, выбранный_хэш, счётчики) if вариант=='A' else модуль.сверить(
                        ф.вход, выбранный_хэш, статистика=счётчики)
                    if результат!=эталон: raise ValueError('диагностика изменила результат')
                    диагностика[вариант] = счётчики
                if проверки.снимок(ф.каталог)!=до: raise ValueError('диагностика записала входы')
                # Отрицательное равенство вне таймеров, на том же сохранённом выборе.
                оригинал = ф.вход.read_bytes(); отрицательное = dict(ф.выбор, лишнее=True)
                ф.вход.write_bytes(проверки.байты(отрицательное)); причины = []
                for действие in (lambda: штатное_чтение(ф, модуль, проверки.хэш(ф.вход.read_bytes())),
                        lambda: модуль.сверить(ф.вход, проверки.хэш(ф.вход.read_bytes()))):
                    до_отказа = проверки.снимок(ф.каталог)
                    try: действие()
                    except ValueError as ошибка: причины.append(str(ошибка))
                    if проверки.снимок(ф.каталог)!=до_отказа: raise ValueError('отказ записал входы')
                ф.вход.write_bytes(оригинал)
                if len(причины)!=2 or причины[0]!=причины[1]: raise ValueError('неравные отказы')
                поздние = поздние_отказы(ф, модуль, проверки, выбранный_хэш)
                клон = проверки.чистый_клон(ф); до_клона = проверки.снимок(ф.каталог)
                начало = time.perf_counter_ns(); процесс = проверки.запустить(ф, каталог=клон)
                холодный = time.perf_counter_ns()-начало
                if процесс.returncode!=0 or json.loads(процесс.stdout)!=эталон: raise ValueError('холодный результат')
                if проверки.снимок(ф.каталог)!=до_клона: raise ValueError('холодный процесс записал входы')
                удалённый = ф.каталог / 'remote.git'
                subprocess.run(['git', 'init', '-q', '--bare', str(удалённый)], check=True)
                ф.гит('remote', 'add', 'origin', str(удалённый)); ф.гит('push', '-q', 'origin', ф.параметры['ветка'])
                ф.выбор['публикация'] = {'адрес_sha256': проверки.хэш(проверки.байты(str(удалённый)))}; проверки.сохранить(ф)
                до_удалённого = проверки.снимок(ф.каталог); начало = time.perf_counter_ns()
                доставка = модуль.сверить(ф.вход, проверки.хэш(ф.вход.read_bytes()))
                время_доставки = time.perf_counter_ns()-начало
                ожидаемая_доставка = {**эталон, 'публикация': {'коммит': ф.итог['коммит'], 'ветка': ф.параметры['ветка'],
                    'адрес_sha256': ф.выбор['публикация']['адрес_sha256'], 'код_push': None}}
                if доставка!=ожидаемая_доставка or проверки.снимок(ф.каталог)!=до_удалённого: raise ValueError('readback')
                профиль['сценарии'].append({'сценарий': 'слияние' if слияние else 'обычный', 'подготовка_наносекунды': подготовка,
                    'измерения': измерения, 'медианы_наносекунды': {в: int(statistics.median(
                        и['наносекунды'] for и in измерения if и['вариант']==в)) for в in ('A', 'B')},
                    'диагностика': диагностика, 'холодный_процесс_наносекунды': холодный,
                    'код_холодного_процесса': процесс.returncode, 'равенство_отказа': True,
                    'поздние_отказы': поздние,
                    'выбор_локальный_sha256': выбранный_хэш, 'выбор_readback_sha256': проверки.хэш(ф.вход.read_bytes()),
                    'readback_наносекунды': время_доставки, 'входы_sha256': ф.выбор['файлы'],
                    'результат_sha256': проверки.хэш(проверки.байты(эталон)), 'неизменность': True})
            finally:
                владелец.doCleanups()
        for имя, хэш in профиль['замыкание'].items():
            if проверки.хэш((проверки.КОРЕНЬ / имя).read_bytes())!=хэш: raise ValueError('дрейф кода после замеров')
        # Из публичных данных убираются физические приватные адреса фикстуры.
        for сценарий in профиль['сценарии']:
            сценарий['входы_sha256'] = {к: в['sha256'] for к, в in сценарий['входы_sha256'].items()}
        установить(выход, проверки.байты(профиль))
        sys.stdout.write(json.dumps({'схема': профиль['схема'], 'сценарии': [
            {к: с[к] for к in ('сценарий', 'медианы_наносекунды', 'неизменность')} for с in профиль['сценарии']]}, ensure_ascii=False)+'\n')
        return 0
    except (ValueError, OSError, ImportError, subprocess.SubprocessError) as ошибка:
        return отказ(str(ошибка))



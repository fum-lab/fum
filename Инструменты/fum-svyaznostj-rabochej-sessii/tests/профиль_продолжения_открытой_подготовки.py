def сохранить_сырые_данные(данные):
    каталог = Path(tempfile.mkdtemp(prefix='fum-профиль-сырые-', dir='/private/tmp' if sys.platform == 'darwin' else None))
    свидетельства = {}
    for имя, сырые in данные.items():
        файл = каталог / имя
        with os.fdopen(os.open(файл, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600), 'wb') as поток:
            поток.write(сырые); поток.flush(); os.fsync(поток.fileno())
        требовать(файл.read_bytes() == сырые, 'не сохранены сырые данные профиля')
        свидетельства[имя] = {'sha256': хэш(сырые), 'байтов': len(сырые)}
    return свидетельства


def запустить_процесс_образца(аргументы):
    каталог = Path(tempfile.mkdtemp(prefix='fum-профиль-сырые-',
        dir='/private/tmp' if sys.platform == 'darwin' else None))
    потоки = {}; процесс = None; ошибка = None; ошибки_сохранения = []; синхронизация = {}
    начало = time.perf_counter_ns()
    def отказ_сохранения(имя, стадия, причина):
        nonlocal ошибка
        ошибки_сохранения.append({'канал': имя, 'стадия': стадия, 'тип': type(причина).__name__,
            'сообщение_sha256': хэш(str(причина).encode())})
        if ошибка is None: ошибка = причина
    try:
        for имя in ('stdout.bin', 'stderr.bin'):
            потоки[имя] = os.fdopen(os.open(каталог / имя,
                os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600), 'wb')
        процесс = subprocess.Popen(аргументы, stdout=потоки['stdout.bin'],
            stderr=потоки['stderr.bin'], shell=False, start_new_session=True)
        процесс.wait()
    except (*повтор.ОШИБКИ, KeyboardInterrupt) as причина:
        ошибка = причина
        if isinstance(причина, KeyboardInterrupt):
            signal.signal(signal.SIGINT, signal.SIG_IGN)
    finally:
        if процесс is not None and процесс.poll() is None:
            for номер, предел in ((signal.SIGINT, 5), (signal.SIGTERM, 2), (signal.SIGKILL, None)):
                try:
                    try: os.killpg(процесс.pid, номер)
                    except ProcessLookupError: pass
                    процесс.wait(timeout=предел); break
                except subprocess.TimeoutExpired: continue
                except OSError as причина: отказ_сохранения(None, 'остановка процесса', причина)
        длительность = time.perf_counter_ns() - начало
        for имя, поток in потоки.items():
            синхронизация[имя] = False
            try:
                поток.flush(); os.fsync(поток.fileno()); синхронизация[имя] = True
            except OSError as причина: отказ_сохранения(имя, 'flush/fsync', причина)
            finally:
                try: поток.close()
                except OSError as причина: отказ_сохранения(имя, 'close', причина)
    сырые = {}
    for имя in потоки:
        try: сырые[имя] = (каталог / имя).read_bytes()
        except OSError as причина: отказ_сохранения(имя, 'чтение обратно', причина)
    каналы = {имя: {'sha256': хэш(данные), 'байтов': len(данные)} for имя, данные in сырые.items()}
    return {'процесс': subprocess.CompletedProcess(аргументы, процесс.returncode if процесс is not None else None,
            сырые.get('stdout.bin'), сырые.get('stderr.bin')),
        'длительность_нс': длительность, 'каналы': каналы, 'ошибка': ошибка,
        'ошибки_сохранения': ошибки_сохранения, 'синхронизация_каналов': синхронизация}


def ручной_отпечаток(файл):
    состояние = файл.lstat()
    требовать(stat.S_ISREG(состояние.st_mode), 'необычный закреплённый файл ручного допуска')
    return {'sha256': хэш(файл.read_bytes()), 'режим': stat.S_IMODE(состояние.st_mode)}


def ручной_допуск(план):
    п = план['технические_входы']['коммит']; корень = Path(п['корень'])
    фасад.проверить_корневой_контур(п, корень, план['контур'] == 'обычный')
    _, _, грязные = коммит.охват.прочитать_статус(корень)
    требовать(set(грязные) <= set(п['разрешённые_цели']), 'late dirty вне T')
    индекс = Path(фасад.поручения._гит(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index'))
    требовать(хэш(индекс.read_bytes()) == план['снимок']['индекс_sha256'], 'late индекс')
    for путь, ожидание in план['снимок']['файлы'].items():
        файл = Path(путь)
        факт = ручной_отпечаток(файл) if os.path.lexists(файл) else None
        требовать(факт == ожидание, 'late байты')
    требовать(not any(os.path.lexists(путь) for путь in (план['отсутствующая_готовность'],
        п['квитанция'], план['исходная_квитанция'])), 'late ready/receipt')
    слияние = Path(фасад.поручения._гит(корень, 'rev-parse', '--absolute-git-dir')) / 'MERGE_HEAD'
    требовать((хэш(слияние.read_bytes()) if os.path.lexists(слияние) else None) == план['снимок']['MERGE_HEAD']
        and хэш(индекс.read_bytes()) == план['снимок']['индекс_sha256'], 'late Git')
    фасад.проверить_корневой_контур(п, корень, план['контур'] == 'обычный')



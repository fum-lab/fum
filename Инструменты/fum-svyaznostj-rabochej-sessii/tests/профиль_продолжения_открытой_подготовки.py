def подготовить_фикстуру(владелец, контур):
    # Базовая фикстура очищает все GIT_*; внешний env не закрепляет даты.
    # Только bootstrap реального Git получает одинаковые даты коммитов.
    класс = фикстуры.база.база.СозданиеКоммита
    исходный_гит = класс.гит
    def гит_с_датой(сам, *аргументы):
        with подмена.dict(os.environ, {'GIT_AUTHOR_DATE': '2026-09-16T00:00:00+03:00',
                'GIT_COMMITTER_DATE': '2026-09-16T00:00:00+03:00'}):
            return исходный_гит(сам, *аргументы)
    with подмена.object(класс, 'гит', гит_с_датой):
        return фикстуры.ОткрытаяФикстура(владелец, контур=контур)



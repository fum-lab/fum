"""Ранний отказ до дорогого источника и сохранение прежних квитанций."""
import json
import subprocess
from pathlib import Path
import unittest
from unittest import mock

import test_создание_коммита as база


class РаннийСоставКоммита(unittest.TestCase):
    def setUp(сам):
        сам.фикстура = база.СозданиеКоммита()
        сам.фикстура.setUp()
        сам.addCleanup(сам.фикстура.doCleanups)

    def test_неполный_состав_останавливает_до_источника(сам):
        ф = сам.фикстура
        ф.готовить()
        ф.запрос.write_text(ф.запрос.read_text().replace("- [Данные](../../данные.txt).\n", ""))
        with mock.patch.object(база.коммит, "команды", side_effect=AssertionError("Достигнут дорогой источник")) as источник:
            ф.отказ_без_коммита(ф.создать)
        источник.assert_not_called()
        сам.assertFalse(Path(ф.параметры["квитанция"]).exists())

    def test_подготовка_требует_явного_состава(сам):
        ф = сам.фикстура
        ф.параметры.pop("разрешённые_цели", None)
        ф.отказ_без_коммита(lambda: база.коммит.подготовить(ф.параметры))
        сам.assertFalse(Path(ф.параметры["сообщение"]).exists())

    def test_дрейф_после_источника_останавливает_до_индекса(сам):
        ф = сам.фикстура
        ф.готовить()
        исходные = база.коммит.команды

        def прочитать_и_изменить(параметры):
            результат = исходные(параметры)
            (ф.корень / "данные.txt").write_text("поздняя подмена\n")
            return результат

        with mock.patch.object(база.коммит, "команды", side_effect=прочитать_и_изменить), \
             mock.patch.object(база.коммит, "индекс", side_effect=AssertionError("Достигнут дорогой индекс")) as индекс:
            ф.отказ_без_коммита(ф.создать)
        индекс.assert_not_called()

    def прежняя_подготовка(сам, версия=1):
        ф = сам.фикстура
        путь = Path(ф.параметры["подготовка"])
        данные = json.loads(путь.read_bytes())
        данные["схема"] = f"fum.подготовленный-коммит.{версия}"
        данные.pop("имя_автора", None)
        if версия == 1:
            данные["параметры"]["схема"] = "fum.создание-коммита.1"
            данные["параметры"].pop("разрешённые_цели", None)
        сырой = база.коммит.байты(данные)
        путь.write_bytes(сырой)
        return сырой

    def test_прежняя_подготовка_без_квитанции_не_создаёт_коммит(сам):
        ф = сам.фикстура
        ф.готовить()
        сам.прежняя_подготовка()
        with mock.patch.object(база.коммит, "команды", side_effect=AssertionError("Прежний вход дошёл до источника")):
            with сам.assertRaisesRegex(база.коммит.ОшибкаКоммита, "новая подготовка"):
                ф.создать()
        сам.assertEqual(ф.начало, ф.гит("rev-parse", "HEAD").strip())

    def test_прежняя_квитанция_восстанавливается_без_нового_допуска(сам):
        ф = сам.фикстура
        ф.готовить()
        итог = ф.создать()
        # Синтетическое прежнее представление, связанное с настоящим Git-объектом.
        сырой = сам.прежняя_подготовка()
        путь = Path(ф.параметры["квитанция"])
        квитанция = json.loads(путь.read_bytes())
        квитанция["подготовка_sha256"] = база.коммит.хэш(сырой)
        путь.write_bytes(база.коммит.байты(квитанция))
        with mock.patch.object(база.коммит, "команды", side_effect=AssertionError("Повтор дошёл до источника")):
            повтор = ф.создать()
        сам.assertEqual(итог["коммит"], повтор["коммит"])

    def test_v2_без_квитанции_требует_новую_подготовку(сам):
        ф = сам.фикстура
        ф.готовить()
        сам.прежняя_подготовка(2)
        ф.отказ_без_коммита(ф.создать)
        сам.assertFalse(Path(ф.параметры["квитанция"]).exists())

    def test_v2_с_историческим_автором_сверяет_буквальную_квитанцию(сам):
        ф = сам.фикстура
        ф.готовить()
        итог = ф.создать()
        # Временная фикстура старого Git-объекта и квитанции; рабочая история не затрагивается.
        объект = ф.гит("cat-file", "commit", итог["коммит"])
        объект = объект.replace("author FUM Интегратор [gpt-6-astra; effort=ultra] <", "author FUM Интегратор <", 1)
        прежний = subprocess.check_output(["git", "-C", str(ф.корень), "hash-object", "-t", "commit", "-w", "--stdin"], input=объект, text=True).strip()
        ф.гит("update-ref", ф.параметры["ветка"], прежний, итог["коммит"])
        сырой = сам.прежняя_подготовка(2)
        путь = Path(ф.параметры["квитанция"])
        квитанция = json.loads(путь.read_bytes())
        квитанция["подготовка_sha256"] = база.коммит.хэш(сырой)
        квитанция["ожидание"]["автор"][0] = "FUM Интегратор"
        путь.write_bytes(база.коммит.байты(квитанция))
        with mock.patch.object(база.коммит, "наблюдать_модель", side_effect=AssertionError("Историческому автору нельзя назначать текущую модель")):
            повтор = ф.создать()
        сам.assertEqual(прежний, повтор["коммит"])
        сам.assertTrue(повтор["автор"].startswith("FUM Интегратор <"))

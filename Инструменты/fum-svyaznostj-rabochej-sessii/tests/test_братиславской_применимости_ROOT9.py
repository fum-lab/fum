"""Настоящий ROOT9: ASCII start, наполнение, v4, связность и READY."""
import contextlib
import io
import json
import os
from pathlib import Path
from unittest import mock
import unittest

import test_независимой_контрольной_точки as т


class БратиславскаяПрименимостьROOT9(unittest.TestCase):
    def стенд(сам):
        м, р, _, вход, выбор = т.НезависимыйФасад.стенд(сам, False)
        import имя_обычного_журнала as имена

        корень = р.ф.корень
        корень_кода = Path(т.__file__).resolve().parents[3]
        прежний_запрос = р.п['запрос']
        прежняя_папка = Path(прежний_запрос).parent.as_posix()
        открытая = р.п['контракт_журнала']['открытая']
        метка = вход['начало']['метка']
        заголовок = вход['начало']['заголовок']
        транслитерация = имена.штатно_преобразовать(корень_кода, [метка])[0]
        префикс = открытая['журнал'].split('_MSK_', 1)[0]
        имя = префикс + '_msk_' + имена.нормализовать(транслитерация)
        новая_папка = 'Журнал/' + имя
        команды = м.корневые_команды(р.п)
        _, план_пары = р.ж.отрендерить_пару_2(
            корень, имя, метка, заголовок, р.п['задача'],
            [к['текст'] for к in команды],
            писатель=м.коммит.исполнитель(р.п), основание=открытая['основание'])
        сам.assertEqual('fum.план-обычной-независимой-пары.2', план_пары['схема'])
        каталоги = план_пары['имя']['каталоги']

        def перенести_собственную_цель(цель):
            начало = прежняя_папка + '/'
            if not цель.startswith(начало):
                return цель
            части = цель[len(начало):].split('/')
            if части[0] == 'материалы':
                части[0] = каталоги['материалы']
                if len(части) > 1 and части[1] == 'запуски-проверок':
                    части[1] = каталоги['запуски-проверок']
            return новая_папка + '/' + '/'.join(части)

        р.п['разрешённые_цели'] = [перенести_собственную_цель(ц)
            for ц in р.п['разрешённые_цели']]
        р.п['история_модели'] = перенести_собственную_цель(р.п['история_модели'])
        р.п['запрос'] = перенести_собственную_цель(прежний_запрос)
        р.п['контракт_журнала']['открытая'] = план_пары
        р.ф.запрос = корень / р.п['запрос']
        наполнение = json.loads(Path(вход['наполнение']).read_bytes())
        наполнение['запрос'] = р.п['запрос']
        наполнение['ожидаемые_цели'] = [перенести_собственную_цель(ц)
            for ц in наполнение['ожидаемые_цели']]
        разрешение = Path(наполнение['разрешение']['путь'])
        разрешение.write_bytes(м.байты(р.п['разрешённые_цели']))
        разрешение.chmod(0o600)
        наполнение['разрешение']['sha256'] = м.хэш(разрешение.read_bytes())
        for путь, данные in ((вход['вход_коммита'], р.п),
                (вход['контракт_журнала'], р.п['контракт_журнала']),
                (вход['наполнение'], наполнение)):
            файл = Path(путь)
            файл.write_bytes(м.байты(данные))
            файл.chmod(0o600)
        return м, р, вход, выбор, план_пары, каталоги

    def test_копия_S_в_новом_maker_не_заменяет_внешний_выбор(сам):
        м, р, вход, выбор, _, _ = сам.стенд()
        р.п['контракт_журнала']['состав']['sha256'] = 'a' * 64
        for путь, данные in ((вход['вход_коммита'], р.п),
                (вход['контракт_журнала'], р.п['контракт_журнала'])):
            Path(путь).write_bytes(м.байты(данные))
        до = т.снимок(р.ф.корень)
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=т.база.ЗАДАЧА):
            with сам.assertRaisesRegex(ValueError, 'копия состава не заменяет независимый выбор ROOT'):
                м.построить_план(вход, выбранный_состав=выбор)
        сам.assertEqual(до, т.снимок(р.ф.корень))
        сам.assertFalse(р.ф.запрос.parent.exists())

    def test_реальный_фасад_новой_пары_сохраняет_полный_допуск(сам):
        м, р, вход, выбор, план_пары, каталоги = сам.стенд()
        корень = р.ф.корень

        штатное_исполнение = м.исполнить_команду

        def команда_фикстуры(аргументы, корень_команды):
            # Согласуется только временный namespace READY между CLI и API.
            if len(аргументы) > 2 and аргументы[2] == str(Path(м.коммит.__file__)):
                код = ('import sys;from pathlib import Path;'
                    'sys.path.insert(0,sys.argv[1]);'
                    'import готовность_коммита as г;'
                    'г.КОРЕНЬ_СОСТОЯНИЯ=Path(sys.argv[2]);'
                    'import создание_коммита as м;'
                    'sys.argv=[м.__file__,*sys.argv[3:]];'
                    'raise SystemExit(м.главная())')
                аргументы = [аргументы[0], '-B', '-I', '-c', код,
                    str(Path(м.коммит.__file__).parent),
                    str(т.готовность.КОРЕНЬ_СОСТОЯНИЯ), *аргументы[3:]]
            return штатное_исполнение(аргументы, корень_команды)

        до = т.снимок(корень)
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=т.база.ЗАДАЧА):
            план = м.построить_план(вход, выбранный_состав=выбор)
            сам.assertEqual(до, т.снимок(корень))
            with contextlib.redirect_stdout(io.StringIO()), mock.patch.object(
                    м, 'исполнить_команду', команда_фикстуры):
                итог = м.выполнить(вход, план, м.хэш(м.байты(план)), выбранный_состав=выбор)
        print(json.dumps({'схема': 'fum.наблюдение-ROOT9-имени.1', 'код': итог['код'],
            'стадии': [{к: з[к] for к in ('стадия', 'код', 'длительность_наносекунды') if к in з}
                for з in итог['стадии']]}, ensure_ascii=False))
        сам.assertEqual(0, итог['код'], итог)
        сам.assertTrue(all(з['код'] == 0 for з in итог['стадии']), итог)
        свойства = р.ж._свойства(р.ф.запрос.read_text())
        сам.assertEqual(план_пары['имя'], свойства['имя'])
        сам.assertEqual('# Исходный запрос 2026-09-16 14:00:00 MSK - Проверить независимый коммит',
            р.ф.запрос.read_text().splitlines()[0])
        каталог_RAW = р.ф.запрос.parent / каталоги['материалы'] / каталоги['запуски-проверок']
        записи = sorted((json.loads(п.read_bytes()) for п in каталог_RAW.glob('*.json')),
            key=lambda з: з['порядок'])
        сам.assertEqual([1, 2], [з['порядок'] for з in записи])
        сам.assertEqual(['fum.test-run.v4'] * 2, [з['схема'] for з in записи])
        for каталог in р.ф.запрос.parent.rglob('*'):
            if каталог.is_dir():
                относительный = каталог.relative_to(р.ф.запрос.parent).as_posix()
                сам.assertTrue(относительный.isascii())
                сам.assertEqual(относительный.lower(), относительный)
        сам.assertFalse((р.ф.запрос.parent / 'материалы').exists())
        готово = next(з['результат'] for з in итог['стадии']
            if з['стадия'] == 'Объявить прежнюю ROOT готовность')
        обёртка = json.loads(Path(готово['путь']).read_bytes())
        сам.assertEqual('fum.готовность-независимой-контрольной-точки.1', обёртка['схема'])
        сам.assertEqual(1, len(обёртка['доказательства_поколений']))
        сам.assertFalse(Path(р.п['квитанция']).exists())
        сам.assertTrue(all((корень / п).read_bytes() == б for п, б in р.прежние.items()))


if __name__ == '__main__':
    unittest.main()

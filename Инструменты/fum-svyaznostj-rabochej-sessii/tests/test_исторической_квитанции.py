    def test_позднее_наблюдение_модели_читается_отрезком(сам):
        # Большое промежуточное событие не требуется перечитывать ради одного наблюдения.
        промежуток = кодировать({'type': 'response_item', 'payload': {'type': 'message',
            'role': 'assistant', 'content': [{'type': 'text', 'text': 'x' * (17 * 1024 * 1024)}]}})
        запись = copy.deepcopy(сам.записи[1])
        запись['timestamp'] = '2026-10-04T00:00:00Z'
        байты = кодировать(запись)
        начало = sum(map(len, сам.строки)) + len(промежуток)
        сам.нативный.write_bytes(b''.join(сам.строки) + промежуток + байты)
        модель = {**сам.модель, 'время': запись['timestamp'], 'позиция': {
            'начало': начало, 'конец': начало + len(байты), 'sha256': хэш(байты)}}
        история = кодировать({'схема': 'fum.история-модели.1', 'задача': ИСПОЛНИТЕЛЬ,
            'последнее': модель, 'число_наблюдений': 2})
        (сам.репозиторий / сам.параметры['история_модели']).write_bytes(история)
        сам.гит('add', сам.параметры['история_модели'])
        дерево = сам.гит('write-tree').strip()
        сырой = сам.сырой.replace(('tree ' + сам.квитанция['результат']['дерево']).encode(),
            ('tree ' + дерево).encode(), 1)
        исторический = сам.гит('hash-object', '-t', 'commit', '-w', '--stdin', ввод=сырой).strip()
        поздний = сам.гит('commit-tree', дерево, '-p', исторический, ввод='Поздний HEAD\n'.encode()).strip()
        сам.гит('update-ref', сам.ветка, поздний, сам.поздний)
        сам.подготовка.update(модель=модель, наблюдений=2, история_sha256=хэш(история))
        сам.квитанция['подготовка_sha256'] = хэш(кодировать(сам.подготовка))
        сам.квитанция['ожидание']['дерево'] = дерево
        сам.квитанция['результат'].update(коммит=исторический, дерево=дерево)
        сам.квитанция['наблюдённый_коммит'] = исторический
        сам.выбор.update(исторический_коммит=исторический, ожидаемый_HEAD=поздний)
        сам.сохранить(); сам.закрепить()
        профиль = {}
        до = сам.снимок()
        загрузить().прочитать(сам.выбор, профиль=профиль)
        сам.assertEqual(до, сам.снимок())
        сам.assertLess(профиль['прочитано_байтов_файлов'], 100000)



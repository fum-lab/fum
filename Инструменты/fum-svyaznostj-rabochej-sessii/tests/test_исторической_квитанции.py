def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def кодировать(данные):
    return (json.dumps(данные, ensure_ascii=False, sort_keys=True) + '\n').encode()


def загрузить():
    описание = importlib.util.spec_from_file_location('историческая_квитанция', СКРИПТ)
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    return модуль



    def гит(сам, *аргументы, ввод=None):
        процесс = subprocess.run(['git', '-C', str(сам.репозиторий), *аргументы], input=ввод,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=10)
        if процесс.returncode:
            raise RuntimeError(процесс.stderr.decode())
        return процесс.stdout.decode()

    def сохранить(сам):
        for имя, данные in [('вход', сам.параметры), ('подготовка', сам.подготовка), ('квитанция', сам.квитанция)]:
            сам.пути[имя].write_bytes(кодировать(данные))
            сам.пути[имя].chmod(0o600)

    def закрепить(сам):
        сам.выбор['файлы'] = {имя: {'путь': str(путь), 'sha256': хэш(путь.read_bytes())}
            for имя, путь in сам.пути.items()}

    def снимок(сам):
        return {str(путь): (путь.read_bytes(), путь.stat().st_mode, путь.stat().st_ino)
            for путь in сам.каталог.rglob('*') if путь.is_file()}

    def прочитать(сам, выбор=None):
        до = сам.снимок()
        try:
            return загрузить().прочитать(сам.выбор if выбор is None else выбор)
        finally:
            сам.assertEqual(до, сам.снимок(), 'читатель изменил файлы или создал побочный результат')


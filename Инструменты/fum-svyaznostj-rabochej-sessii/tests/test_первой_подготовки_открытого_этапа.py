class ПерваяПодготовкаОткрытогоЭтапа(unittest.TestCase):
    def открытый_стенд(сам):
        помощник = независимые.НезависимыйФасад()
        сам.addCleanup(помощник.doCleanups)
        модуль, рабочий, _, вход, выбор = помощник.стенд()
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
            первый = модуль.построить_план(вход, выбранный_состав=выбор)
            модуль._установить_новую_пару(вход, первый, выбор)
            модель = рабочий.ф.корень / рабочий.п['история_модели']
            модель.parent.mkdir(exist_ok=True)
            рабочий.м.наблюдать_модель(рабочий.п, без_записи=False)
            for номер, код in enumerate((1, 0)):
                идентификатор = [вход['проверки'][0]['идентификатор'],
                    вход['связность']['идентификатор']][номер]
                with contextlib.redirect_stdout(io.StringIO()):
                    результат = рабочий.м.отчёты.выполнить_запуск(
                        рабочий.ф.корень, рабочий.ф.запрос,
                        'Сохранить прежний исход ' + str(номер + 1),
                        'фикстура', идентификатор, 15,
                        [sys.executable, '-B', '-c', 'raise SystemExit(' + str(код) + ')'],
                        класс_проверки='адресная', приёмочные_раунды=True)
                сам.assertEqual(код, результат)
        прежние = {}
        for файл, запись, сырые in модуль.история(рабочий.ф.корень, рабочий.п['запрос'])[1]:
            прежние[файл.relative_to(рабочий.ф.корень).as_posix()] = сырые
        сам.assertEqual(2, len(прежние))
        новые = ['00000000-0000-0000-0000-000000000043',
            '00000000-0000-0000-0000-000000000044']
        будущие = [(рабочий.ф.запрос.parent / 'материалы/запуски-проверок'
            / (str(номер) + '_' + идентификатор + '.json')).relative_to(
                рабочий.ф.корень).as_posix()
            for номер, идентификатор in enumerate(новые, 3)]
        параметры = copy.deepcopy(рабочий.п)
        параметры['разрешённые_цели'] += будущие
        Path(вход['вход_коммита']).write_bytes(модуль.байты(параметры))
        наполнение = json.loads(Path(вход['наполнение']).read_bytes())
        разрешение = Path(наполнение['разрешение']['путь'])
        разрешение.write_bytes(модуль.байты(параметры['разрешённые_цели']))
        наполнение['разрешение']['sha256'] = hashlib.sha256(разрешение.read_bytes()).hexdigest()
        наполнение['ожидаемые_цели'] = будущие
        Path(вход['наполнение']).write_bytes(модуль.байты(наполнение))
        вход['схема'] = 'fum.фасад-открытой-независимой-контрольной-точки.1'
        вход['проверки'][0].update(идентификатор=новые[0], порядок=3)
        вход['связность'].update(идентификатор=новые[1], порядок=4)
        вход['готовность']['проверки'] = новые
        return модуль, рабочий, вход, выбор, прежние, будущие

    def test_читающий_план_продолжает_после_двух_реальных_исходов(сам):
        модуль, рабочий, вход, выбор, прежние, будущие = сам.открытый_стенд()
        до = снимок(рабочий.ф.корень)
        курсор = Path(рабочий.п['кэш_модели'])
        курсор_до = (курсор.read_bytes(), курсор.stat().st_mode)
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
            план = модуль.построить_план(вход, выбранный_состав=выбор)
        сам.assertTrue(план['открытая_подготовка'])
        сам.assertEqual(будущие, план['будущие_цели'])
        сам.assertEqual(до, снимок(рабочий.ф.корень))
        сам.assertEqual(курсор_до, (курсор.read_bytes(), курсор.stat().st_mode))
        сам.assertFalse(Path(рабочий.п['подготовка']).exists())
        сам.assertFalse(Path(рабочий.п['квитанция']).exists())
        сам.assertEqual(set(прежние), {з['путь'] for з in план['история_открытого_этапа']})
        for путь, сырые in прежние.items():
            сам.assertEqual(сырые, (рабочий.ф.корень / путь).read_bytes())
            запись = next(з for з in план['история_открытого_этапа'] if з['путь'] == путь)
            сам.assertEqual(hashlib.sha256(сырые).hexdigest(), запись['sha256'])

    def исполнить_команду_фикстуры(сам, модуль, аргументы, корень):
        if len(аргументы) > 2 and аргументы[2] == str(Path(модуль.коммит.__file__)):
            код = ('import sys;from pathlib import Path;sys.path.insert(0,sys.argv[1]);'
                'import готовность_коммита as г;г.КОРЕНЬ_СОСТОЯНИЯ=Path(sys.argv[2]);'
                'import создание_коммита as м;sys.argv=[м.__file__,*sys.argv[3:]];raise SystemExit(м.главная())')
            аргументы = [аргументы[0], '-B', '-I', '-c', код,
                str(Path(модуль.коммит.__file__).parent), str(готовность.КОРЕНЬ_СОСТОЯНИЯ),
                *аргументы[3:]]
        return сам.штатная_команда(аргументы, корень)

    def test_реальная_первая_подготовка_до_READY_сохраняет_RED_и_модель(сам):
        м, р, вход, выбор, прежние, будущие = сам.открытый_стенд()
        модель = р.ф.корень / р.п['история_модели']; модель_до = модель.read_bytes()
        сам.штатная_команда = м.исполнить_команду
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
            план = м.построить_план(вход, выбранный_состав=выбор)
            with contextlib.redirect_stdout(io.StringIO()), mock.patch.object(м, 'исполнить_команду',
                    side_effect=lambda а, к: сам.исполнить_команду_фикстуры(м, а, к)):
                итог = м.выполнить(вход, план, м.хэш(м.байты(план)), выбранный_состав=выбор)
        сам.assertEqual(0, итог['код'], итог)
        сам.assertFalse(итог['коммит_создан'])
        сам.assertEqual('fum.подготовленный-коммит.11', м.прочитать(р.п['подготовка'])['схема'])
        сам.assertTrue(готовность.путь_этапа(р.п).is_file())
        сам.assertFalse(Path(р.п['квитанция']).exists())
        сам.assertEqual(модель_до, модель.read_bytes())
        сам.assertEqual(р.п['исходный_коммит'], р.ф.гит('rev-parse', 'HEAD').strip())
        сам.assertEqual(прежние, {п: (р.ф.корень / п).read_bytes() for п in прежние})
        сам.assertTrue(all((р.ф.корень / п).is_file() for п in будущие))
        стадии = [з['стадия'] for з in итог['стадии']]
        сам.assertLess(стадии.index('Построить immutable fill-plan'),
            стадии.index('Подготовить источники и модель'))
        сам.assertLess(стадии.index('Предварительный терминальный предпросмотр'),
            стадии.index('Подготовить источники и модель'))

    def test_дрейф_прежнего_RAW_отказывает_до_исполнения(сам):
        м, р, вход, выбор, прежние, _ = сам.открытый_стенд()
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
            план = м.построить_план(вход, выбранный_состав=выбор)

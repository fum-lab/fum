class Стенд(СценарийПисателя):
    хэш_выбора: str
    ошибка_полного_ответа: bool
    ответ_отправки: dict
    def __init__(сам, папка):
        super().__init__(папка)
        сам.нативный = сам.папка / 'native.jsonl'
        текст = 'Конечное поручение ROOT.'
        акт = json.loads((сам.репо / сам.ожидание['поручение']['путь']).read_bytes())
        акт['хэш_нативного_поручения'] = живое.канон.хэш(текст.encode())
        выбор = {**сам.сохранить(сам.ожидание['поручение']['путь'], испытание.байты(акт)),
            'координатор': КООРДИНАТОР, 'исполнитель': ДОЧЬ}
        сам.изменить(поручение=выбор)
        сам.ожидание.update(поручение=выбор,
            решение_координатора=сам.вход['исполнители'][0]['решение_координатора'])
        # Первоначальный C и literal остаются отдельными от поздней постановки.
        записи = [
            {'type':'session_meta','payload':{'id':ДОЧЬ,'cwd':str(сам.дерево),
                'thread_source':'agent_created_thread','git':{'commit_hash':акт['постановка']['коммит']}}},
            {'type':'turn_context','payload':{'cwd':str(сам.дерево),'model':'gpt-6.1-sol','effort':'ultra'}},
            {'type':'response_item','payload':{'type':'function_call_output','name':'create_thread',
                'output':f'<codex_delegation>\n  <source_thread_id>{КООРДИНАТОР}</source_thread_id>\n  <input>{текст}</input>\n</codex_delegation>'}}]
        сам.нативный.write_bytes(b''.join(испытание.байты(з) for з in записи))
        сам.нативный.chmod(0o600)
        сам.выбор = сам.папка / 'выбор.json'
        сам.закрепить()
        сам.объекты = сам.папка / 'RAW'; сам.объекты.mkdir(mode=0o700)
        сам.контейнер = object.__new__(узел.КонтейнерПроцессов)
        сам.контейнер.корень = сам.объекты
        сам.поток = живое.ПотокМоста(io.BytesIO(), io.BytesIO())
        сам.вызовы = []
        сам.сбой = None
        сам.позднее = None
        сам.ошибка_полного_ответа = False
        сам.ответ_отправки = {'content':[{'type':'text','text':'{"ok":true}'}]}

    def закрепить(сам, **замены):
        данные = {'схема':'fum.выбор-живого-восстановления.1',
            'ожидание_sha256':живое.канон.хэш(испытание.байты(сам.ожидание)),
            'хранилище':str(сам.хранилище),
            'нативный':{'путь':str(сам.нативный),'размер':сам.нативный.stat().st_size,
                'sha256':живое.канон.хэш(сам.нативный.read_bytes())},
            'контроль_координатора':{'корень':str(сам.репо),'ref':гит(сам.репо,'symbolic-ref','HEAD'),
                'HEAD':гит(сам.репо,'rev-parse','HEAD')},
            'начало':int(time.time())-5,'конец':int(time.time())+300}
        данные.update(замены)
        сам.выбор.write_bytes(испытание.байты(данные)); сам.выбор.chmod(0o600)
        сам.хэш_выбора = живое.канон.хэш(сам.выбор.read_bytes())

    def сырой(сам, новый=False):
        описание = сам.снимок(ДОЧЬ, ходы=[сам.ход('ход-2' if новый else 'ход-1',
            статус='completed' if новый else 'interrupted', текст='')])
        оболочка=json.loads((сам.снимки / описание['путь']).read_bytes())
        ответ=json.loads(оболочка['content'][0]['text']);ответ['page']['limit']=1
        оболочка['content'][0]['text']=json.dumps(ответ,ensure_ascii=False)
        return испытание.байты(оболочка)

    def вызов(сам, фаза, параметры):
        сам.вызовы.append((фаза,copy.deepcopy(параметры)))
        if фаза == 'read2' and сам.позднее:
            сам.позднее()
        if фаза == 'send':
            with (сам.папка / 'отправки').open('ab') as ф: ф.write(b'1\n'); ф.flush(); os.fsync(ф.fileno())
            if сам.сбой == 'после отправки': os._exit(71)
            return испытание.байты(сам.ответ_отправки)
        return сам.сырой(фаза == 'readback')

    def сохранить_полный_ответ(сам, описание, данные):
        (сам.объекты / описание['идентификатор']).write_bytes(данные)
        if сам.сбой == 'после RAW send' and описание['тип'] == 'codex-send_message_to_thread': os._exit(72)
        return {'описание':описание,'размер':len(данные),'хэш':живое.канон.хэш(данные)}

    def извлечь_полный_ответ(сам, имя):
        return 'повреждено'.encode() if сам.ошибка_полного_ответа else (сам.объекты / имя).read_bytes()

    def выполнить(сам, профиль=None):
        with patch.object(живое.ПотокМоста,'вызвать',side_effect=сам.вызов), \
                patch.object(узел.КонтейнерПроцессов,'сохранить',side_effect=сам.сохранить_полный_ответ), \
                patch.object(узел.КонтейнерПроцессов,'извлечь',side_effect=сам.извлечь_полный_ответ):
            return живое.восстановить(сам.ожидание,сам.хэш_выбора,корень=сам.репо,выбор=сам.выбор,
                поток=сам.поток,контейнер=сам.контейнер,профиль=профиль)

    def путь_намерения(сам):
        return сам.хранилище / (живое.канон.хэш(испытание.байты({'задача':ДОЧЬ}))+'.json')

    def сохранить_стенд(сам):
        имена=('папка','репо','дерево','снимки','нативный','выбор','хранилище','объекты')
        данные={к:str(getattr(сам,к)) for к in имена}
        данные.update(ожидание=сам.ожидание,хэш_выбора=сам.хэш_выбора)
        (сам.папка/'стенд.json').write_bytes(испытание.байты(данные))

    @classmethod
    def загрузить(класс, папка):
        данные=json.loads((Path(папка)/'стенд.json').read_bytes());сам=object.__new__(класс)
        for к in ('папка','репо','дерево','снимки','нативный','выбор','хранилище','объекты'):setattr(сам,к,Path(данные[к]))
        сам.ожидание=данные['ожидание'];сам.хэш_выбора=данные['хэш_выбора']
        сам.контейнер=object.__new__(узел.КонтейнерПроцессов);сам.контейнер.корень=сам.объекты
        сам.поток=живое.ПотокМоста(io.BytesIO(),io.BytesIO())
        сам.вызовы=[];сам.сбой=None;сам.позднее=None;сам.ошибка_полного_ответа=False
        сам.ответ_отправки={'content':[{'type':'text','text':'{"ok":true}'}]}
        return сам



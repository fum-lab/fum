class РеальныйНезависимыйСоздатель(unittest.TestCase):
    СТАДИИ_СВЕРОК = (
        'независимый журнал: историческая привязка',
        'независимый журнал: после адреса',
        'независимый журнал: перед наличием готовности',
        'независимый журнал: перед эффектом',
        'последний допуск: 1',
        'последний допуск: 2',
        'последний допуск: 3',
    )

    @contextlib.contextmanager
    def наблюдать_создание(сам):
        наблюдение = {'флаги': [], 'измерения': []}
        штатная_сверка = сам.м.сверить_независимый_журнал
        штатный_измеритель = сам.м.измерить

        def сверить(*аргументы, **поля):
            наблюдение['флаги'].append(поля.get('новый_эффект', True))
            return штатная_сверка(*аргументы, **поля)

        def измерить(профиль, название, действие, *аргументы, **поля):
            try:
                return штатный_измеритель(профиль, название, действие, *аргументы, **поля)
            finally:
                наблюдение['измерения'].append(dict(профиль[-1]))

        with mock.patch.object(сам.м, 'сверить_независимый_журнал', сверить), \
                mock.patch.object(сам.м, 'измерить', измерить):
            yield наблюдение

    def проверить_измерения(сам, наблюдение, флаги, стадии, исходы=None):
        сам.assertEqual(флаги, наблюдение['флаги'])
        выбранные = [з for з in наблюдение['измерения'] if з['стадия'] in сам.СТАДИИ_СВЕРОК]
        сам.assertEqual(list(стадии), [з['стадия'] for з in выбранные])
        сам.assertEqual(['успех'] * len(выбранные) if исходы is None else исходы,
            [з['исход'] for з in выбранные])
        for запись in наблюдение['измерения']:
            сам.assertIs(type(запись['длительность_наносекунды']), int)
            сам.assertGreaterEqual(запись['длительность_наносекунды'], 0)
        return выбранные


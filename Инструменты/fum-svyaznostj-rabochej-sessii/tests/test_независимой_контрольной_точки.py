            папка.mkdir(exist_ok=True)
            архив = папка / 'архив.json'; архив.write_text('{"состояние":"архив"}\n')
            исполняемый = папка / 'артефакт.py'; исполняемый.write_text('print("Открытый артефакт")\n'); исполняемый.chmod(0o755)

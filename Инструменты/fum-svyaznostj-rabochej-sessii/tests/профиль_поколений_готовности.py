"""Профиль чистых поколений, приватного сохранения и настоящего Git-допуска."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import statistics
import time

from test_поколения_готовности import ПоколенияГотовности, поколения
from test_создание_коммита import СозданиеКоммита, ЗАПУСК, коммит


def измерить(выход):
    корень = Path(__file__).resolve().parents[1]
    пути = [Path(__file__), *[корень / "scripts" / имя for имя in (
        "готовность_этапа.py", "поколения_готовности.py", "готовность_коммита.py",
        "создание_коммита.py", "история_модели.py", "сообщения_задачи.py")],
        *[корень / "tests" / имя for имя in ("test_поколения_готовности.py", "test_создание_коммита.py", "test_готовность_этапа.py")]]
    исходники = {str(п.relative_to(корень)): hashlib.sha256(п.read_bytes()).hexdigest() for п in пути}
    наблюдения = []
    пример = ПоколенияГотовности(); пример.setUp()
    for число in (1, 10, 100):
        состояние = пример.состояние
        for номер in range(1, число):
            состояние = поколения.отозвать(состояние, номер - 1, "Повторная проверка", пример.время + номер * 2)
            состояние = поколения.объявить("/фикстура", пример.снимок, пример.записи,
                пример.время + номер * 2 + 1, 600, прежнее=состояние)
        серии = []
        for _ in range(5):
            начало = time.perf_counter_ns()
            for _ in range(20):
                _, решение = поколения.оценить(состояние, пример.снимок, пример.время + 700_000_000_000)
            серии.append((time.perf_counter_ns() - начало) / 20)
            assert решение["фиксировать_этап"] and решение["задержка"]
        наблюдения.append({"сценарий": "чистая сверка", "поколений": число,
            "серии_наносекунды": серии, "медиана_наносекунды": statistics.median(серии)})
    случай = СозданиеКоммита()
    try:
        случай.setUp(); случай.готовить(объявить_готовность=False)
        начало = time.perf_counter_ns()
        готовность = коммит.объявить_готовность(Path(случай.параметры["подготовка"]), [ЗАПУСК], 600)
        наблюдения.append({"сценарий": "объявление по реальному индексу", "длительность_наносекунды": time.perf_counter_ns() - начало})
        состояние = коммит.готовность.прочитать(Path(готовность["путь"]))
        поколение = состояние["поколения"][-1]
        серии = []
        for _ in range(5):
            начало = time.perf_counter_ns()
            решение = коммит.готовность.сверить(случай.параметры, поколение["снимок"], поколение["записи"])
            серии.append(time.perf_counter_ns() - начало)
            assert решение["фиксировать_этап"]
        наблюдения.append({"сценарий": "сверка с замком и fsync", "серии_наносекунды": серии,
            "медиана_наносекунды": statistics.median(серии)})
        начало = time.perf_counter_ns()
        итог = случай.создать()
        длительность = time.perf_counter_ns() - начало
        квитанция = json.loads(Path(случай.параметры["квитанция"]).read_bytes())
        assert квитанция["состояние"] == "проверен" and квитанция["готовность"]["фиксировать_этап"]
        assert итог["коммит"] == случай.гит("rev-parse", "HEAD").strip()
        наблюдения.append({"сценарий": "создание с настоящим Git", "длительность_наносекунды": длительность,
            "стадии": квитанция["профиль"]})
    finally:
        случай.doCleanups()
    assert исходники == {str(п.relative_to(корень)): hashlib.sha256(п.read_bytes()).hexdigest() for п in пути}
    итог = {"схема": "fum.профиль-поколений-готовности.1", "исходники": исходники,
        "версия_интерпретатора": platform.python_version(), "архитектура": platform.machine(),
        "граница": "Чистые функции: пять серий по двадцать вызовов; подготовка состояний исключена. Приватная сверка: пять вызовов с чтением, замком и fsync. Объявление и Git-создание: по одному вызову на реальной временной фикстуре, её подготовка исключена. Сеть не вызывается, кэш ОС не очищается, стадии вложены в полный вызов и отдельно к нему не суммируются.",
        "наблюдения": наблюдения}
    выход.write_text(json.dumps(итог, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    измерить(разбор.parse_args().выход)

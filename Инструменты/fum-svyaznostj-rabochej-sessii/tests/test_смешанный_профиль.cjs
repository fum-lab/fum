"use strict";
const {test: проверить} = require("node:test");
const утверждать = require("node:assert/strict");
const {свести} = require("./профиль-смешанных-ответов.cjs");

проверить("Сводка считает каждую выдачу и уникальные файлы отдельно", () => {
    const шаги = [
        {режим: "новый", размер: "малый", полезные_байты: 2000, полные_байты: 500, длительность_мс: 100,
            вызовы: {симулированный_api: 1, запись_файла: 1, команда: 3, загрузка_кэша: 0, запись_кэша: 2}},
        {режим: "новый", размер: "крупный", полезные_байты: 3000, полные_байты: 4000000, длительность_мс: 200,
            вызовы: {симулированный_api: 1, запись_файла: 1, команда: 3, загрузка_кэша: 0, запись_кэша: 2}},
        {режим: "сохранённый", размер: "крупный", полезные_байты: 3000, полные_байты: 4000000, длительность_мс: 50,
            вызовы: {симулированный_api: 0, запись_файла: 0, команда: 1, загрузка_кэша: 1, запись_кэша: 1}}
    ];
    const итог = свести(шаги, [{байты: 500}, {байты: 4000000}]);
    утверждать.equal(итог.байты_модельной_выдачи, 8000);
    утверждать.equal(итог.байты_полных_выдач, 8000500);
    утверждать.equal(итог.байты_уникальных_файлов, 4000500);
    утверждать.equal(итог.время_мс, 350);
    утверждать.equal(итог.вызовы.симулированный_api, 2);
    утверждать.equal(итог.вызовы.команда, 7);
    утверждать.equal(итог.живые_api, 0);
});

проверить("Неверные измерения не становятся доказательством экономии", () => {
    утверждать.throws(() => свести([], []));
    утверждать.throws(() => свести([{режим: "новый", размер: "малый", полезные_байты: -1}], []));
});

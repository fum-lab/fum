"""Сравнить полную сериализацию и страницу на одном открытом входе."""
import argparse
import copy
import hashlib
import json
import statistics
import sys
import time
import tracemalloc
from pathlib import Path

from test_компактный_остаток import снимок, байты
from компактный_остаток import представить, закодировать


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    параметры = разбор.parse_args()
    значение = снимок()
    образец = значение["сообщения"][0]
    сообщения = []
    for номер in range(400):
        сообщение = copy.deepcopy(образец)
        сообщение["экземпляр"] = hashlib.sha256(f"открытый-экземпляр-{номер}".encode()).hexdigest()
        сообщение["позиция"] = {"начало": номер * 100, "конец": (номер + 1) * 100, "sha256": "a" * 64}
        сообщение["содержимое"] = [{"type": "input_text", "text": f"Команда {номер}: сохрани исходное сообщение.\n"}]
        сообщение["сырой_объект"] = {"нагрузка": "открытая фикстура " * 50}
        сообщения.append(сообщение)
    экземпляры = [сообщение["экземпляр"] for сообщение in сообщения]
    значение["сообщения"] = сообщения
    значение["контекст"].update({"экземпляры": экземпляры, "граница": 40000})
    значение["граница_заключительной_сверки"] = 40000
    значение["остаток"] = [{"экземпляр": экземпляр, "причины": ["нет записи обработки"],
        "поздние": экземпляры[номер + 1:], "последняя_обработка": None}
        for номер, экземпляр in enumerate(экземпляры)]
    данные = байты(значение)
    хэш = hashlib.sha256(данные).hexdigest()

    def полный():
        assert hashlib.sha256(данные).hexdigest() == хэш
        return байты(json.loads(данные))

    def компактный():
        return закодировать(представить(данные, хэш, начало=390, число=10))

    функции = {"полная_сериализация": полный, "страница": компактный}
    замеры = {имя: [] for имя in функции}
    выходы = {}
    for повтор in range(7):
        for имя in (tuple(функции) if повтор % 2 == 0 else tuple(reversed(функции))):
            начало = time.perf_counter_ns()
            выходы[имя] = функции[имя]()
            замеры[имя].append(time.perf_counter_ns() - начало)
    память = {}
    for имя, функция in функции.items():
        tracemalloc.start()
        функция()
        память[имя] = tracemalloc.get_traced_memory()[1]
        tracemalloc.stop()
    assert выходы["полная_сериализация"] == данные
    страница = json.loads(выходы["страница"])
    assert страница["всего_необработанных"] == 400
    assert страница["непоказанных_необработанных"] == 390
    assert [сообщение["оригинал"]["экземпляр"] for сообщение in страница["сообщения"]] == экземпляры[390:]
    каталог = Path(__file__).resolve().parents[1]
    исходники = {имя: hashlib.sha256((каталог / имя).read_bytes()).hexdigest() for имя in
        ("scripts/компактный_остаток.py", "scripts/показать-остаток.py", "tests/test_компактный_остаток.py",
         "tests/профиль_компактного_остатка.py")}
    результат = {"схема": "fum.профиль-компактного-остатка.1", "Python": sys.version.split()[0],
        "вход_sha256": хэш, "вход_байты": len(данные), "исходники_sha256": исходники,
        "начало": 390, "число": 10, "всего_сообщений": 400, "повторы": 7,
        "длительности_наносекунды": замеры,
        "медианы_наносекунды": {имя: statistics.median(замер) for имя, замер in замеры.items()},
        "пиковые_байты_Python": память,
        "выходные_байты": {имя: len(выход) for имя, выход in выходы.items()},
        "выходные_sha256": {имя: hashlib.sha256(выход).hexdigest() for имя, выход in выходы.items()},
        "семантическая_сверка": True,
        "граница": "Один неизменный синтетический вход. Подготовка и запись исключены; хэш, разбор и сериализация включены. Память Python измерена отдельно от времени. Страница показывает 10 из 400 сообщений, остальные сохранены в полном артефакте. Это не измерение токенов, качества модели, RSS или полного допуска."}
    параметры.выход.parent.mkdir(parents=True, exist_ok=True)
    параметры.выход.write_bytes(байты(результат))
    print(json.dumps({ключ: результат[ключ] for ключ in
        ("вход_байты", "выходные_байты", "медианы_наносекунды", "пиковые_байты_Python", "семантическая_сверка")}, ensure_ascii=False))


if __name__ == "__main__":
    выполнить()

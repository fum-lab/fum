    def test_служебный_retry_до_и_после_append_не_оставляет_пропусков(сам):
        for вид in ('проверка','итог'):
            for после in (False,True):
                with сам.subTest(вид=вид,после=после):
                    сам.контейнер=ПамятьКаталога(); сам.контейнер.потерять_ответ=True
                    сохранить=сам.контейнер.сохранить; попытки=[]; отказ=[False]
                    def запись(описание,данные):
                        целевой=описание['тип']=='fum-каталог-цикла' and json.loads(данные)['вид']==вид
                        if целевой: попытки.append((copy.deepcopy(описание),данные))
                        if целевой and not отказ[0]:
                            отказ[0]=True
                            if после: сохранить(описание,данные)
                            raise OSError('подконтрольный неизвестный исход служебной записи')
                        return сохранить(описание,данные)
                    сам.контейнер.сохранить=запись
                    вызовы=[]; цикл=сам.новый()
                    цикл.наблюдать(lambda запрос:(вызовы.append(запрос),сам.ответ())[1],источник='фикстура')
                    цикл.повторить_доставку(вызовы[0]['threadId'])
                    новый=сам.новый().итог()
                    сам.assertEqual(len(вызовы),1)
                    сам.assertEqual(новый['каталог']['циклы'][0]['итог'],'подтверждён')
                    сам.assertEqual(новый['история'][0]['ACK_прежнего_процесса'],'подтверждён')
                    сам.assertEqual(попытки[0],попытки[1])


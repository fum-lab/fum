import unittest

import test_состояние_задач_узла as прежние


class ПамятьКаталога(прежние.ПамятьКонтейнера):
    def перечень(сам):
        return {"схема": "fum.перечень-контейнера.1", "неполный_хвост": False,
            "записи": [{"описание": copy.deepcopy(описание), "размер": len(данные),
                "хэш": __import__('hashlib').sha256(данные).hexdigest()}
                for описание, данные in сам.записи.values()]}


class КаталогПослеПрерывания(unittest.TestCase):
    подготовить_испытание = прежние.ОжиданияУзла.подготовить_испытание
    сохранить = прежние.ОжиданияУзла.сохранить
    ответ = прежние.ЦиклКонтроллера.ответ
    def setUp(сам):
        сам.подготовить_испытание()
        сам.контейнер = ПамятьКаталога()

    def новый(сам):
        модуль = importlib.import_module('состояние_задач_узла')
        return модуль.ЦиклНаблюдения(сам.доверие, корень=сам.с.репо, контейнер=сам.контейнер)

    def test_новый_процесс_находит_историю_без_ручного_перечня(сам):
        старый = сам.новый().наблюдать(lambda запрос: сам.ответ(), источник='подконтрольная фикстура')
        новый = сам.новый().итог()
        сам.assertEqual(len(новый['история']), 1)
        сам.assertEqual(новый['история'][0]['объект'], старый['наблюдения'][0]['объект'])
        сам.assertFalse(новый['история'][0]['свежее_в_этом_цикле'])
        сам.assertEqual(новый['каталог']['циклы'][0]['итог'], 'подтверждён')
        сам.assertEqual(новый['история'][0]['ACK_прежнего_процесса'], 'подтверждён')
        сам.assertEqual(новый['наблюдения'], [])
        сам.assertFalse(новый['каталог']['полнота_перечня'])

    def test_прерывание_после_начала_не_пустой_успех(сам):
        def оборвать(запрос):
            raise KeyboardInterrupt('моделируем остановку процесса после durable start')
        with сам.assertRaises(KeyboardInterrupt): сам.новый().наблюдать(оборвать, источник='фикстура')
        итог = сам.новый().итог()
        сам.assertEqual(len(итог['каталог']['циклы']), 1)
        сам.assertEqual(итог['каталог']['циклы'][0]['итог'], 'unknown')
        сам.assertEqual(итог['история'][0]['ACK_прежнего_процесса'], 'unknown')
        сам.assertIsNone(итог['история'][0]['объект'])

    def test_неизвестный_ACK_начала_блокирует_чтение(сам):
        сохранить = сам.контейнер.сохранить
        def потерять(описание, данные):
            сохранить(описание, данные)
            raise OSError('потерян ACK начала')
        сам.контейнер.сохранить = потерять
        вызовы = []
        with сам.assertRaises((ValueError, OSError)):
            сам.новый().наблюдать(lambda запрос: вызовы.append(запрос), источник='фикстура')
        сам.assertEqual(вызовы, [])
        сам.assertEqual(сам.новый().итог()['каталог']['циклы'][0]['итог'], 'unknown')

    def test_RAW_после_аварии_не_доказывает_ACK(сам):
        цикл = сам.новый()
        with patch.object(цикл, 'зафиксировать_проверку', side_effect=KeyboardInterrupt):
            with сам.assertRaises(KeyboardInterrupt): цикл.наблюдать(lambda запрос: сам.ответ(), источник='фикстура')
        итог = сам.новый().итог()
        сам.assertIsNotNone(итог['история'][0]['объект'])
        сам.assertEqual(итог['история'][0]['ACK_прежнего_процесса'], 'unknown')
        сам.assertEqual(итог['каталог']['циклы'][0]['итог'], 'unknown')

    def test_потерянный_ACK_RAW_сохраняет_unknown_и_локальный_повтор(сам):
        сам.контейнер.потерять_ответ = True
        цикл = сам.новый(); вызовы = []
        цикл.наблюдать(lambda запрос: (вызовы.append(запрос), сам.ответ())[1], источник='фикстура')
        старый = сам.новый().итог()
        сам.assertIsNotNone(старый['история'][0]['объект'])
        сам.assertEqual(старый['история'][0]['ACK_прежнего_процесса'], 'unknown')
        цикл.повторить_доставку(вызовы[0]['threadId'])
        новый = сам.новый().итог()
        сам.assertEqual(новый['история'][0]['ACK_прежнего_процесса'], 'подтверждён')
        сам.assertEqual(len(вызовы), 1)
        попытки = [x for x in сам.контейнер.попытки if x[0]['тип'] == 'codex-read_thread']
        сам.assertEqual(попытки[0], попытки[1])

    def test_найденный_итог_без_ACK_остаётся_unknown(сам):
        сохранить = сам.контейнер.сохранить
        def потерять(описание, данные):
            ответ = сохранить(описание, данные)
            if описание['тип'] == 'fum-каталог-цикла' and json.loads(данные)['вид'] == 'итог':
                raise OSError('receipt итога потерян после записи')
            return ответ
        сам.контейнер.сохранить = потерять
        первый = сам.новый().наблюдать(lambda запрос: сам.ответ(), источник='фикстура')
        сам.assertEqual(первый['исход_каталога_текущего_цикла'], 'unknown')
        второй = сам.новый().итог()
        сам.assertEqual(второй['каталог']['циклы'][0]['итог'], 'unknown')
        сам.assertEqual(второй['история'][0]['ACK_прежнего_процесса'], 'подтверждён')

    def test_хвост_не_даёт_пустой_успех_и_не_чинится(сам):
        сам.новый().наблюдать(lambda запрос: сам.ответ(), источник='фикстура')
        перечень = сам.контейнер.перечень
        def с_хвостом():
            результат = перечень(); результат['неполный_хвост'] = True; return результат
        сам.контейнер.перечень = с_хвостом
        до = copy.deepcopy(сам.контейнер.записи)
        цикл = сам.новый(); сам.assertEqual(цикл.итог()['каталог']['циклы'][0]['итог'], 'unknown')
        вызовы = []
        with сам.assertRaises(ValueError): цикл.наблюдать(lambda запрос: вызовы.append(запрос), источник='фикстура')
        сам.assertEqual(вызовы, []); сам.assertEqual(сам.контейнер.записи, до)

    def test_подмены_SHA_описания_узла_цикла_и_ACK_отказывают(сам):
        сам.новый().наблюдать(lambda запрос: сам.ответ(), источник='фикстура')
        исходные = copy.deepcopy(сам.контейнер.записи)
        for что in ('байты', 'описание', 'узел', 'цикл', 'ACK-себя', 'ACK-вперёд'):
            with сам.subTest(что=что):
                сам.контейнер.записи = copy.deepcopy(исходные)
                if что in ('байты', 'описание', 'узел', 'цикл'):
                    ключ = next(k for k,(o,d) in сам.контейнер.записи.items() if o['тип'] == 'codex-read_thread')
                    описание, данные = сам.контейнер.записи[ключ]
                    if что == 'байты': данные += b' '
                    elif что == 'описание': описание['время'] = 'подмена'
                    else:
                        тело = json.loads(base64.b64decode(описание['спецификация']))
                        тело[что] = 'чужой'; описание['спецификация'] = base64.b64encode(json.dumps(тело).encode()).decode()
                    сам.контейнер.записи[ключ] = (описание, данные)
                else:
                    модуль = importlib.import_module('каталог_наблюдений_узла')
                    ключ = next(k for k,(o,d) in сам.контейнер.записи.items() if o['тип'] == модуль.ТИП and json.loads(d)['вид'] == 'ACK-итога')
                    описание, данные = сам.контейнер.записи[ключ]; тело = json.loads(данные)
                    тело['цель'] = {'идентификатор': ключ if что == 'ACK-себя' else 'будущий'}
                    данные = модуль.кодировать(тело)
                    описание['спецификация'] = base64.b64encode(модуль.кодировать({'схема':тело['схема'], 'sha256':модуль.хэш(данные)})).decode()
                    сам.контейнер.записи[ключ] = описание, данные
                with сам.assertRaises(ValueError): сам.новый()
        сам.контейнер.записи = исходные

    def test_точный_повтор_служебной_записи_идемпотентен(сам):
        цикл = сам.новый()
        вход = цикл.каталог.событие(цикл.цикл, 'начало', 0, '2026-10-09T00:00:00Z',
            адресаты=[], параметры={}, полнота_перечня=False)
        первая = цикл.каталог.сохранить(вход); до = copy.deepcopy(сам.контейнер.записи)
        сам.assertEqual(цикл.каталог.сохранить(вход), первая)
        сам.assertEqual(сам.контейнер.записи, до)
        with сам.assertRaises(ValueError): цикл.каталог.сохранить((вход[0], вход[1]+b' '))


    def test_неполная_установка_сохраняет_первый_файл(сам):
        план=сам.м.построить_план(сам.вход); файл=сам.выходы/'план.json'
        файл.write_bytes(сам.м.байты(план)); файл.chmod(0o400)
        старый=os.open
        def отказ(путь,флаги,*а,**к):
            if str(путь)==str(сам.выходы/'вход-коммита.json') and флаги&os.O_CREAT: raise OSError('Прерывание установки')
            return старый(путь,флаги,*а,**к)
        with mock.patch.object(os,'open',side_effect=отказ):
            with сам.assertRaises(OSError): сам.м.применить(сам.вход,файл,сам.м.хэш(файл.read_bytes()))
        сам.assertTrue((сам.ф.корень/сам.решение['постановка']['путь']).exists())
        сам.assertFalse((сам.выходы/'вход-коммита.json').exists())
        сам.м.применить(сам.вход,файл,сам.м.хэш(файл.read_bytes()))


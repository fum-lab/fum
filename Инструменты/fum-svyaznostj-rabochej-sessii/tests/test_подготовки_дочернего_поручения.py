    def подготовить_акт(сам):
        пост=сам.решение['постановка']; путь=сам.ф.корень/пост['путь']
        тело=пост['текст']; хэш_содержимого=сам.м.этап.свежесть.content_digest(сам.м.этап.свежесть.canonical_content(тело))
        путь.write_text(сам.м.этап.свежесть.attach_recency_block(тело,'2026-09-16 00:00:00 MSK',хэш_содержимого))
        сам.ф.ф.гит('add',пост['путь']); сам.ф.ф.гит('commit','-qm','Первоначальная постановка')
        выбор={'коммит':сам.ф.ф.гит('rev-parse','HEAD').strip(),'путь':пост['путь'],'sha256':сам.м.хэш(путь.read_bytes())}
        ребёнок=сам.ф.приватный/'ребёнок'; сам.ф.ф.гит('worktree','add','--detach',str(ребёнок),выбор['коммит'])
        идентификатор='00000000-0000-0000-0000-000000000022'
        сам.нативный=сам.ф.приватный/'ребёнок.jsonl'
        сам.события=[{'type':'session_meta','payload':{'id':идентификатор,'cwd':str(ребёнок),'thread_source':'agent_created_thread','git':{'commit_hash':выбор['коммит']}}},
            {'type':'turn_context','timestamp':'2026-09-16T21:00:00Z','payload':{'cwd':str(ребёнок),'model':сам.решение['модель'],'effort':сам.решение['усилие']}},
            {'type':'response_item','timestamp':'2026-09-16T21:00:01Z','payload':{'type':'function_call_output','name':'create_thread','output':'<codex_delegation>\n  <source_thread_id>'+сам.решение['координатор']+'</source_thread_id>\n  <input>'+сам.м.приглашение(сам.решение,выбор)+'</input>\n</codex_delegation>'}}]
        сам.нативный.write_text(''.join(json.dumps(э,ensure_ascii=False)+'\n' for э in сам.события))
        каталог=сам.ф.приватный/'акт-выходы'; каталог.mkdir(mode=0o700)
        сам.вход.update(фаза='акт',постановка=выбор,исполнитель={'задача':идентификатор,'корень':str(ребёнок),'источник_модели':str(сам.нативный)},каталог_выходов=str(каталог))
        return выбор

    def test_акт_после_фактического_исполнителя_и_независимый_выбор(сам):
        выбор=сам.подготовить_акт(); план=сам.м.построить_план(сам.вход)
        приглашение=сам.м.составить_приглашение(сам.ф.корень,сам.вход['решение'],выбор)
        сам.assertEqual(сам.м.приглашение(сам.решение,выбор),приглашение['текст'])
        сам.assertEqual(сам.решение['модель'],приглашение['модель'])
        сам.assertEqual(выбор['sha256'],план['источники']['постановка']['сырой_sha256'])
        сам.assertNotEqual(выбор['sha256'],план['источники']['постановка']['хэш_содержимого'])
        файл=Path(сам.вход['каталог_выходов'])/'план.json'; файл.write_bytes(сам.м.байты(план)); файл.chmod(0o400)
        сам.м.применить(сам.вход,файл,сам.м.хэш(файл.read_bytes()))
        сам.ф.ф.гит('add',сам.решение['акт']['путь']); сам.ф.ф.гит('commit','-qm','ACT после native')
        коммит=сам.ф.ф.гит('rev-parse','HEAD').strip()
        выбранный=сам.м.выбрать_акт(сам.ф.корень,коммит,сам.решение['акт']['путь'],сам.решение['координатор'],сам.вход['исполнитель']['задача'])
        сам.assertEqual(коммит,выбранный['коммит']); сам.assertNotEqual(выбор['коммит'],коммит)
        акт=сам.м.обычное.прочитать_акт(сам.ф.корень,выбранный)
        сам.assertNotIn('коммит',акт); сам.assertEqual(выбор,акт['постановка'])


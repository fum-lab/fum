        Path(источник['кэш']).unlink()
        снимок=сам.м.этап.коммит.сообщения.прочитать_сообщения(источник['путь'],источник['задача'],
            корень_репозитория=сам.ф.корень,кэш=источник['кэш'])
        экземпляры=[э['экземпляр'] for э in снимок['сообщения'] if э['происхождение']=='человек']
        источник.update(экземпляры=экземпляры,граница_снимка={'граница':снимок['граница'],'sha256':снимок['sha256'],
            'неоднозначные_экземпляры':[э['экземпляр'] for э in снимок['сообщения'] if э['происхождение']!='человек']})
        from обработка_сообщений import контекст_снимка
        import основание_двусторонней_координации as основание
        with open(источник['путь'],'rb') as поток: начало=поток.readline()
        сам.решение.update(схема='fum.смысл-дочернего-поручения.2',координация={
            'экземпляры':экземпляры,'начало_корня':{'sha256':сам.м.хэш(начало),'thread_source':'user'},
            'контекст':контекст_снимка(снимок),'решение':{'актуальность':'актуально','поздние':[],
                'основание':'ROOT рассмотрел весь контекст; конечная область сохранена.','область':сам.решение['акт']['область'],'рассмотренные_неоднозначности':[]},
            'хэш_поручения':сам.м.хэш(сам.решение['поручение'].encode()),'адресат':сам.решение['координатор'],
            'сообщения':['результат','препятствие'],'получение':'подтверждение требуется','ограничения':основание.ОГРАНИЧЕНИЯ})
        оригиналы=[]
        for э in снимок['сообщения']:
            if э['экземпляр'] not in экземпляры: continue
            файл=сам.ф.приватный/(э['экземпляр']+'.raw');позиция=э['позиция']
            with open(источник['путь'],'rb') as поток:
                поток.seek(позиция['начало']);файл.write_bytes(поток.read(позиция['конец']-позиция['начало']))
            файл.chmod(0o600);оригиналы.append({'экземпляр':э['экземпляр'],'путь':str(файл),'sha256':сам.м.хэш(файл.read_bytes())})
        сам.вход.update(схема='fum.подготовка-дочернего-поручения.3',основание_координации={'источник':0,'оригиналы':оригиналы})
        файл=сам.ф.корень/'Планирование/решение.json';файл.write_bytes(сам.м.байты(сам.решение))
        сам.ф.ф.гит('add','Планирование/решение.json');сам.ф.ф.гит('commit','-qm','Сохранить человеческое основание')
        сам.вход['решение'].update(коммит=сам.ф.ф.гит('rev-parse','HEAD').strip(),sha256=сам.м.хэш(файл.read_bytes()))


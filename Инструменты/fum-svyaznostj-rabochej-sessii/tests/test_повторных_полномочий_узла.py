class Пример:
    def __init__(сам, каталог):
        сам.ф = План(каталог); сам.корень = сам.ф.корень; п = сам.ф.план
        папка = Path(п['файлы'][0]['путь']).parent
        сам.документ = {'схема': 'fum.полномочия-ветки-состояния-узла.2',
            **{к: п[к] for к in прежние.ИДЕНТИЧНОСТЬ}, 'ветка': п['ветка'],
            'хэш_корня': п['хэш_корня'], 'начальный_коммит': сам.ф.ф.первоначальный['коммит'],
            'исходный_коммит': п['исходный_коммит'], 'путь': 'expected.json',
            'цели': ['expected.json', *[ф['путь'] for ф in п['файлы']],
                str(папка/'материалы/история-модели.json'), 'Журнал/README.md',
                'Индексы/markdown-файлы-по-времени-редактирования.md',
                str(папка/'материалы/запуски-проверок/1_11111111-1111-4111-8111-111111111111.json')],
            'контрольная_ветка': 'refs/heads/codex/повторные-полномочия', 'план_журнала': сам.ф.выбор}
        сам.старое = {к: в for к, в in сам.документ.items() if к != 'план_журнала'}
        сам.старое.update(схема=прежние.СХЕМА, контрольная_ветка='refs/heads/codex/старые-полномочия')
        сам.старый_выбор = сам.ф.ф.с.сохранить('Планирование/старые-полномочия.json', байты(сам.старое))
        гит(сам.корень, 'branch', 'codex/старые-полномочия', сам.старый_выбор['коммит'])
        сам.сырые = байты(сам.документ)
        сам.выбор = сам.ф.ф.с.сохранить('Планирование/повторные-полномочия.json', сам.сырые)

    def сохранить(сам, документ):
        return сам.ф.ф.с.сохранить('Планирование/повторные-полномочия.json', байты(документ))

    def снимок(сам): return сам.ф.снимок()

    def прочитать(сам, **к): return читатель.прочитать(сам.выбор, корень=сам.корень, **к)


class ПовторныеПолномочия(unittest.TestCase):
    def setUp(сам):
        каталог = tempfile.TemporaryDirectory(prefix='fum-repeated-authority-')
        сам.addCleanup(каталог.cleanup); сам.ф = Пример(каталог.name)

    def test_историческое_чтение_повтор_профиль_и_нулевые_эффекты(сам):
        ф = сам.ф; до = ф.снимок(); профиль = {}
        with patch.object(прежние.гит, 'служебные_состояния', side_effect=AssertionError('Нет live gate')):
            итог = ф.прочитать(профиль=профиль); повтор = ф.прочитать()
        сам.assertEqual(итог, повтор); сам.assertEqual(итог['байты'], ф.сырые)
        сам.assertEqual(итог['документ'], ф.документ); сам.assertFalse(итог['разрешение_установки'])
        сам.assertTrue(итог['строгий_порядок_Git']); сам.assertEqual(до, ф.снимок())
        сам.assertEqual(профиль['API'], 0); сам.assertEqual(профиль['разборов_native'], 0)

    def test_проект_не_доказывает_строгий_порядок_коммитов(сам):
        ф = сам.ф; до = ф.снимок()
        итог = читатель.сверить_проект(ф.сырые, корень=ф.корень)
        сам.assertFalse(итог['строгий_порядок_Git']); сам.assertFalse(итог['разрешение_установки'])
        сам.assertEqual(до, ф.снимок())

    def test_замкнутые_поля_схема_идентичность_H_и_корневой_SHA(сам):
        ф = сам.ф
        for правка in [{'лишнее': True}, {'схема': прежние.СХЕМА}, {'владелец': ф.документ['координатор']},
                {'узел': 'другой-узел'}, {'репозиторий': 'другой-репозиторий'},
                {'координатор': '22222222-2222-4222-8222-222222222222'},
                {'владелец': '33333333-3333-4333-8333-333333333333'},
                {'начальный_коммит': ф.ф.выбор['коммит']},
                {'поколение_полномочий': 'новое'}, {'хэш_корня': '0'*64},
                {'ветка': 'refs/heads/fuma'}, {'исходный_коммит': ф.выбор['коммит']},
                {'контрольная_ветка': 'refs/heads/fuma'}]:
            with сам.subTest(правка=правка), сам.assertRaises(ValueError):
                читатель.сверить_проект(байты({**ф.документ, **правка}), корень=ф.корень)
        with сам.assertRaises(ValueError):
            читатель.сверить_проект('{"схема":1,"схема":2}'.encode(), корень=ф.корень)

    def test_цели_только_одна_новая_пара_и_служебные_файлы(сам):
        ф = сам.ф
        for изменение in ('старая-пара', 'другая-пара', 'builder', 'повтор', 'нет-отчёта'):
            п = copy.deepcopy(ф.документ)
            if изменение == 'старая-пара': п['цели'].append(ф.ф.план['предыдущий_этап']['путь'])
            if изменение == 'другая-пара': п['цели'][1] = 'Журнал/чужой/запрос.md'
            if изменение == 'builder': п['цели'].append(ф.ф.план['строитель'][0]['путь'])
            if изменение == 'повтор': п['цели'].append(п['цели'][0])
            if изменение == 'нет-отчёта': п['цели'].remove(ф.ф.план['файлы'][1]['путь'])
            with сам.subTest(изменение=изменение), сам.assertRaises(ValueError):
                читатель.сверить_проект(байты(п), корень=ф.корень)

    def test_подмена_селектора_P_отклоняется(сам):
        ф = сам.ф
        for правка in [{'sha256': '0'*64}, {'коммит': '0'*40}, {'путь': '../план.json'}]:
            п = {**ф.документ, 'план_журнала': {**ф.ф.выбор, **правка}}
            выбор = ф.сохранить(п)
            with сам.subTest(правка=правка), сам.assertRaises(ValueError):
                читатель.прочитать(выбор, корень=ф.корень)

    def test_строгий_порядок_не_принимает_равенство_коммитов(сам):
        ф = сам.ф; до = ф.снимок(); П = ф.ф.выбор['коммит']; А = ф.выбор['коммит']
        читатель.проверить_порядок(ф.корень, П, А)
        for п, а in [(П, П), (А, П)]:
            with сам.subTest(п=п, а=а), сам.assertRaises(ValueError):
                читатель.проверить_порядок(ф.корень, п, а)
        сам.assertEqual(до, ф.снимок())

    def test_лимит_A_проверяется_до_чтения_blob(сам):
        ф = сам.ф; исходный = прежние.гит.гит
        def размер(корень, *аргументы):
            if аргументы[:2] == ('cat-file', '-s'): return str(1024*1024+1)
            return исходный(корень, *аргументы)
        with patch.object(прежние.гит, 'гит', side_effect=размер), \
                patch.object(прежние.гит, 'объект_файла', side_effect=AssertionError('Рано читать blob')), \
                сам.assertRaises(ValueError): ф.прочитать()

    def test_полные_селекторы_и_конечные_пути_закрыты(сам):
        ф = сам.ф
        for правка in [{'sha256': '0'*64}, {'коммит': ф.выбор['коммит'][:12]},
                {'путь': '../вне.json'}, {'лишнее': True}]:
            with сам.subTest(правка=правка), сам.assertRaises(ValueError):
                читатель.прочитать({**ф.выбор, **правка}, корень=ф.корень)
        for имя in ['expected\n.json', 'expecte\u0301d.json', 'expected:json']:
            п = copy.deepcopy(ф.документ); п['путь'] = имя; п['цели'][0] = имя
            with сам.subTest(имя=имя), сам.assertRaises(ValueError):
                читатель.сверить_проект(байты(п), корень=ф.корень)

    def test_непредковый_коммит_A_отклоняется(сам):
        ф = сам.ф; дерево = гит(ф.корень, 'rev-parse', ф.выбор['коммит']+'^{tree}').strip()
        oid = гит(ф.корень, 'commit-tree', дерево, '-m', 'Независимый корневой коммит').strip()
        with сам.assertRaises(ValueError): читатель.прочитать({**ф.выбор, 'коммит': oid}, корень=ф.корень)

    def test_A2_не_проходит_старые_дерево_и_ACT_при_обоих_флагах(сам):
        ф = сам.ф
        гит(ф.корень, 'branch', 'codex/повторные-полномочия', ф.выбор['коммит'])
        акт = {'схема': 'fum.поручение-дочерней-контрольной-точки.2',
            'полномочия_узла': ф.выбор, 'ветка': ф.документ['ветка'],
            'координатор': ф.документ['координатор'], 'исполнитель': ф.документ['владелец'],
            'постановка': {'коммит': ф.документ['начальный_коммит']}, 'область': ф.документ['цели']}
        for флаг in (False, True):
            with сам.subTest(флаг=флаг):
                with сам.assertRaisesRegex(ValueError, 'неверные поля полномочий'):
                    прежние.прочитать(ф.корень, ф.выбор, новый_эффект=флаг)
                with сам.assertRaisesRegex(ValueError, 'неверные поля полномочий'): прежние.проверить_дерево(ф.корень,
                    ф.документ['владелец'], ф.документ['ветка'], ф.выбор, новый_эффект=флаг)
                for версия in ('.2', '.3'):
                    with сам.assertRaisesRegex(ValueError, 'неверные поля полномочий'):
                        прежние.проверить_акт(ф.корень,
                            {**акт, 'схема': 'fum.поручение-дочерней-контрольной-точки'+версия}, новый_эффект=флаг)

    def test_настоящий_symlink_A_отклоняется(сам):
        ф = сам.ф; п = ф.корень/'Планирование/ссылка-полномочий.json'
        п.symlink_to('повторные-полномочия.json')
        гит(ф.корень, 'add', 'Планирование/ссылка-полномочий.json')
        гит(ф.корень, 'commit', '-m', 'Отвергнуть symlink полномочий')
        до = ф.снимок()
        with сам.assertRaises(ValueError): читатель.прочитать({'коммит': гит(ф.корень, 'rev-parse', 'HEAD').strip(),
            'путь': 'Планирование/ссылка-полномочий.json', 'sha256': хэш('повторные-полномочия.json'.encode())}, корень=ф.корень)
        сам.assertEqual(до, ф.снимок())

    def test_A1_исторически_повторяется_после_смены_control(сам):
        ф = сам.ф
        сам.assertEqual(прежние.прочитать(ф.корень, ф.старый_выбор), ф.старое)
        гит(ф.корень, 'branch', '-f', 'codex/старые-полномочия', ф.документ['исходный_коммит'])
        до = ф.снимок()
        сам.assertEqual(прежние.прочитать(ф.корень, ф.старый_выбор, новый_эффект=False), ф.старое)
        with сам.assertRaises(ValueError): прежние.прочитать(ф.корень, ф.старый_выбор, новый_эффект=True)
        сам.assertEqual(до, ф.снимок())

    def test_грязный_checkout_и_CLI_двумя_процессами(сам):
        ф = сам.ф; (ф.корень/'Планирование/повторные-полномочия.json').write_text('Поздняя подмена\n')
        вход = ф.ф.ф.с.папка/'выбор-A2.json'
        вход.write_bytes(байты({'схема': 'fum.чтение-повторных-полномочий-узла.1', 'полномочия': ф.выбор})); вход.chmod(0o600)
        команда = [sys.executable, '-B', str(Path(читатель.__file__).with_name('проверить_повторные_полномочия_узла.py')),
            '--корень-репозитория', str(ф.корень), '--вход', str(вход)]
        до = ф.снимок(); ответы = [subprocess.run(команда, capture_output=True) for _ in range(2)]
        сам.assertTrue(all(о.returncode == 0 for о in ответы), ответы)
        сам.assertEqual(ответы[0].stdout, ответы[1].stdout)
        сам.assertEqual(json.loads(ответы[0].stdout)['sha256'], хэш(ф.сырые)); сам.assertEqual(до, ф.снимок())
        вход.write_bytes(байты({'схема': 'fum.чтение-повторных-полномочий-узла.1',
            'полномочия': {**ф.выбор, 'sha256': '0'*64}}))
        до = ф.снимок(); отказ = subprocess.run(команда, capture_output=True)
        сам.assertEqual(отказ.returncode, 1); сам.assertEqual(отказ.stdout, b'')
        сам.assertEqual(до, ф.снимок())



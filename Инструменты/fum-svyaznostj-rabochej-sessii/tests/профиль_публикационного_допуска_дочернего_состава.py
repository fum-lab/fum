        номер = 0; результаты = []
        def процесс(задание):
            nonlocal номер
            номер += 1; вход = артефакты / (str(номер) + '-вход.json')
            задание['создатель_sha256'] = хэш(Path(задание['код']).joinpath(СОЗДАТЕЛЬ).read_bytes())
            новый_файл(вход, байты(задание), 0o400)
            р = subprocess.run([sys.executable, '-B', str(Path(__file__).resolve()), '--работник', str(вход)], capture_output=True)
            новый_файл(артефакты / (str(номер) + '-stdout.json'), р.stdout)
            новый_файл(артефакты / (str(номер) + '-stderr.txt'), р.stderr)
            требовать(р.returncode == 0, 'Процесс профиля отказал; сырые исходы сохранены, повтор запрещён')
            д = json.loads(р.stdout)
            return д, {'код': р.returncode, 'stdout_байты': len(р.stdout), 'stderr_байты': len(р.stderr),
                'stdout_sha256': хэш(р.stdout), 'stderr_sha256': хэш(р.stderr)}
        for сценарий in ('чистый', 'запрещённый'):
            исходник = артефакты / ('начало-' + сценарий); исходник.mkdir(mode=0o700)
            исход, _ = процесс({'фаза': 'начало', 'код': str(базовый_код), 'фиксированный': str(фиксированный),
                'назначение': str(исходник), 'сценарий': сценарий})

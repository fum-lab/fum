@contextlib.contextmanager
def ручной_терминальный_допуск(м, допуск, п, публикация):
    """Явная часть A: stock effect и parser сохраняются; допуск добавлен снаружи."""
    гит, преобразовать = м.гит, м.готовность.преобразовать
    сохранить, проверить, восстановить = м.модели.сохранить_сообщение, м.проверить_объект, м.восстановить
    def готовность(параметры, действие, **поля):
        def внутри(прежнее):
            допуск.сверить(публикация(), п, м)
            return действие(прежнее)
        return преобразовать(параметры, внутри, **поля)
    def перед_деревом(корень, *аргументы, **поля):
        if аргументы == ('write-tree',):
            допуск.сверить(публикация(), п, м)
        результат = гит(корень, *аргументы, **поля)
        if аргументы == ('write-tree',):
            допуск.последний_адрес(п, м)
        return результат
    def после_intent(путь, текст):
        результат = сохранить(путь, текст)
        if Path(путь) == Path(п['квитанция']):
            допуск.сверить(публикация(), п, м)
        return результат
    def после_объекта(корень, ожидание, объект):
        результат = проверить(корень, ожидание, объект)
        if sys._getframe(1).f_code == м._зафиксировать_новую_квитанцию.__code__:
            допуск.последний_адрес(п, м, ожидаемый=объект)
        return результат
    def после_replay(корень, квитанция, путь):
        результат = восстановить(корень, квитанция, путь)
        допуск.последний_адрес(п, м, ожидаемый=результат['коммит'])
        return результат
    м.гит, м.готовность.преобразовать = перед_деревом, готовность
    м.модели.сохранить_сообщение, м.проверить_объект, м.восстановить = после_intent, после_объекта, после_replay
    try:
        yield
    finally:
        м.гит, м.готовность.преобразовать = гит, преобразовать
        м.модели.сохранить_сообщение, м.проверить_объект, м.восстановить = сохранить, проверить, восстановить


def загруженные_источники(корни):
    результат = {}
    for имя, модуль in list(sys.modules.items()):
        путь = getattr(модуль, '__file__', None)
        if not путь:
            continue
        ф = Path(путь).absolute()
        if any(ф.is_relative_to(к) for к in корни):
            требовать(ф == ф.resolve() and ф.is_file(), 'Дрейф загруженного исходника')
            д = ф.read_bytes()
            результат[имя] = {'путь': str(ф), 'sha256': хэш(д), 'байты': len(д), 'режим': stat.S_IMODE(ф.stat().st_mode)}
        elif ф.is_relative_to(Path(заданные_источники())):
            raise ValueError('Исполнение из исходного checkout вместо материализованного closure')
    return результат



def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def требовать(условие, пояснение):
    if not условие:
        raise ValueError(пояснение)


def новый_файл(путь, данные, режим=0o600):
    with os.fdopen(os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, режим), 'wb') as ф:
        os.fchmod(ф.fileno(), режим); ф.write(данные); ф.flush(); os.fsync(ф.fileno())


def метаданные(с):
    return (с.st_dev, с.st_ino, с.st_uid, с.st_mode, с.st_size, с.st_mtime_ns, с.st_ctime_ns)


def проверить_родителя(путь, ожидаемый=None):
    требовать(путь.is_absolute() and путь.parent == путь.parent.resolve(), 'Нужен физический приватный выход')
    с = путь.parent.lstat()
    требовать(stat.S_ISDIR(с.st_mode) and с.st_uid == os.getuid() and stat.S_IMODE(с.st_mode) == 0o700,
        'Нужен собственный каталог0700')
    требовать(ожидаемый is None or (с.st_dev, с.st_ino) == ожидаемый, 'Подмена родителя приватного выхода')
    требовать(all(not os.path.lexists(предок / '.git') for предок in (путь.parent, *путь.parent.parents)),
        'Выход находится внутри Git')
    return (с.st_dev, с.st_ino)


def резервировать(путь):
    путь = Path(путь)
    родитель = проверить_родителя(путь)
    дескриптор = os.open(путь, os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    os.fchmod(дескриптор, 0o600)
    шаблон = байты({'схема': 'fum.парный-профиль-публикации.1', 'готов': False})

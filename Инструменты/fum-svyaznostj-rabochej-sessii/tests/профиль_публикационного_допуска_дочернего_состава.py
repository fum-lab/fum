def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def требовать(условие, пояснение):
    if not условие:
        raise ValueError(пояснение)


def новый_файл(путь, данные, режим=0o600):
    with os.fdopen(os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, режим), 'wb') as ф:
        os.fchmod(ф.fileno(), режим); ф.write(данные); ф.flush(); os.fsync(ф.fileno())


def метаданные(с):
    return (с.st_dev, с.st_ino, с.st_uid, с.st_mode, с.st_size, с.st_mtime_ns, с.st_ctime_ns)


def проверить_родителя(путь, ожидаемый=None):
    требовать(путь.is_absolute() and путь.parent == путь.parent.resolve(), 'Нужен физический приватный выход')
    с = путь.parent.lstat()
    требовать(stat.S_ISDIR(с.st_mode) and с.st_uid == os.getuid() and stat.S_IMODE(с.st_mode) == 0o700,
        'Нужен собственный каталог0700')
    требовать(ожидаемый is None or (с.st_dev, с.st_ino) == ожидаемый, 'Подмена родителя приватного выхода')
    требовать(all(not os.path.lexists(предок / '.git') for предок in (путь.parent, *путь.parent.parents)),
        'Выход находится внутри Git')
    return (с.st_dev, с.st_ino)


def резервировать(путь):
    путь = Path(путь)
    родитель = проверить_родителя(путь)
    дескриптор = os.open(путь, os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    os.fchmod(дескриптор, 0o600)
    шаблон = байты({'схема': 'fum.парный-профиль-публикации.1', 'готов': False})
    os.write(дескриптор, шаблон); os.fsync(дескриптор)
    РЕЗЕРВЫ[дескриптор] = (путь, родитель, метаданные(os.fstat(дескриптор)), шаблон)
    return дескриптор


def установить(дескриптор, путь, данные):
    сохранённый_путь, родитель, сохранённые, шаблон = РЕЗЕРВЫ.pop(дескриптор)
    путь = Path(путь)
    требовать(путь == сохранённый_путь, 'Подмена имени приватного выхода')
    проверить_родителя(путь, родитель)
    каталог = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        с = os.fstat(каталог)
        требовать((с.st_dev, с.st_ino) == родитель, 'Подмена открытого родителя')
        с = os.fstat(дескриптор); т = os.stat(путь.name, dir_fd=каталог, follow_symlinks=False)
        требовать(stat.S_ISREG(т.st_mode) and метаданные(с) == сохранённые == метаданные(т)
            and с.st_uid == os.getuid() and stat.S_IMODE(с.st_mode) == 0o600
            and os.pread(дескриптор, с.st_size + 1, 0) == шаблон,
            'Поздняя подмена приватного выхода')
        проверить_родителя(путь, родитель)
        требовать(метаданные(os.fstat(дескриптор)) == сохранённые, 'Поздняя запись приватного выхода')
        os.lseek(дескриптор, 0, os.SEEK_SET); os.ftruncate(дескриптор, 0)
        with os.fdopen(os.dup(дескриптор), 'wb') as ф:
            ф.write(данные); ф.flush(); os.fsync(ф.fileno())
    finally:
        os.close(каталог)


def инвентарь(корень):
    результат = {'.': {'тип': 'каталог', 'режим': stat.S_IMODE(корень.lstat().st_mode)}}
    for ф in sorted(корень.rglob('*')):
        с = ф.lstat()
        требовать(not stat.S_ISLNK(с.st_mode), 'Ссылка в сохранённой фикстуре')
        if stat.S_ISREG(с.st_mode):
            д = ф.read_bytes()
            результат[ф.relative_to(корень).as_posix()] = {'тип': 'файл', 'sha256': хэш(д), 'байты': len(д), 'режим': stat.S_IMODE(с.st_mode)}
        else:
            требовать(stat.S_ISDIR(с.st_mode), 'Необычный объект фикстуры')
            результат[ф.relative_to(корень).as_posix()] = {'тип': 'каталог', 'режим': stat.S_IMODE(с.st_mode)}
    return результат


def восстановить_на_месте(источник, назначение, состав):
    # Native JSONL сохраняет исходный inode, обязательный для model cursor.
    # Остальные файлы возвращаются к точным подготовленным байтам и режимам.
    требовать(назначение.is_dir() and назначение == назначение.resolve(), 'Исходная фикстура исчезла')
    текущий = инвентарь(назначение)
    for имя in sorted(set(текущий) - set(состав), key=lambda и: (и.count('/'), и), reverse=True):
        ф = назначение / имя
        if текущий[имя]['тип'] == 'каталог':
            ф.rmdir()
        else:
            ф.unlink()
    for имя, запись in sorted(состав.items(), key=lambda п: (п[0].count('/'), п[0])):
        ф = назначение / имя; исходный = источник / имя
        if запись['тип'] == 'каталог':
            ф.mkdir(exist_ok=True); ф.chmod(запись['режим'])
        else:
            требовать(not ф.exists() or stat.S_ISREG(ф.lstat().st_mode), 'Дрейф типа сохранённого файла')
            if not ф.exists() or ф.read_bytes() != исходный.read_bytes():
                shutil.copyfile(исходный, ф)
            shutil.copystat(исходный, ф, follow_symlinks=False)
    требовать(инвентарь(назначение) == состав, 'Дрейф точных подготовленных байтов')


def загрузить_адаптер():
    имя = 'публикационный_допуск_дочернего_состава'
    if имя in sys.modules:
        return sys.modules[имя]
    путь = КОРЕНЬ / АДАПТЕР
    модуль = types.ModuleType(имя); модуль.__file__ = str(путь)
    sys.modules[имя] = модуль
    exec(compile(путь.read_bytes(), str(путь), 'exec', dont_inherit=True), модуль.__dict__)
    return модуль



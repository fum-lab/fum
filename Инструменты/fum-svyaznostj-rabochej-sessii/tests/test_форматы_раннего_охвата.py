"""Ранние форматы на открытых Git-фикстурах: без построения проекции."""
import json
import importlib.util
from unittest.mock import patch
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

СКРИПТ = Path(__file__).resolve().parents[1] / 'scripts/проверить-охват-запроса.py'


class ПроверкаФорматов(unittest.TestCase):
    def setUp(сам):
        временный = tempfile.TemporaryDirectory()
        сам.addCleanup(временный.cleanup)
        сам.корень = Path(временный.name)
        сам.гит('init', '-q')
        сам.гит('-c', 'user.name=Тест', '-c', 'user.email=test@example.invalid', 'commit', '--allow-empty', '-qm', 'Основа')
        сам.запрос = 'Журнал/2026-09-19_09-23-00_MSK_проверять-форматы/запрос.md'
        сам.записать(сам.запрос, '# Запрос\n\n## Повлиял на файлы\n\n[Запрос](запрос.md)\n[Отчёт](отчёт.md)\n[Данные](../../Данные/)\n[Инструменты](../../Инструменты/)\n')
        сам.записать(str(Path(сам.запрос).with_name('отчёт.md')), '# Отчёт\n')
        (сам.корень/'Данные').mkdir()
        (сам.корень/'Инструменты').mkdir()

    def гит(сам, *аргументы):
        return subprocess.check_output(['git', '-C', str(сам.корень), *аргументы])

    def записать(сам, путь, текст):
        файл = сам.корень / путь
        файл.parent.mkdir(parents=True, exist_ok=True)
        файл.write_text(текст)
        return файл

    def вызвать(сам):
        результат = subprocess.run([sys.executable, '-B', str(СКРИПТ), '--корень', str(сам.корень), '--запрос', сам.запрос, '--форматы'], capture_output=True, text=True)
        return результат.returncode, результат.stdout, результат.stderr

    def test_обычный_текст_без_построения(сам):
        сам.записать('Данные/текст.md', 'Открытый текст\n')
        код, вывод, ошибка = сам.вызвать()
        сам.assertEqual(код, 0, ошибка + вывод)
        сам.assertTrue(json.loads(вывод)['готов'])
        сам.assertFalse((сам.корень/'Proyekcii').exists())

    def test_неизвестный_формат_отклонён_классификатором(сам):
        сам.записать('Данные/неизвестный.cjs', 'const имя = 1;\n')
        код, вывод, ошибка = сам.вызвать()
        сам.assertEqual(код, 1, ошибка)
        сам.assertIn('Неизвестный формат', вывод)


    def test_собственное_имя_отклонено_внешние_поля_сохранены(сам):
        путь = 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/адаптер_ответа.cjs'
        сам.записать(путь, 'const hidden = 1;\n')
        код, вывод, _ = сам.вызвать()
        сам.assertEqual(код, 1)
        сам.assertIn('латинские объявления', вывод)
        сам.записать(путь, 'const ответ = {id: "пример", kind: "codex", status: {type: "active"}};\n')
        код, вывод, ошибка = сам.вызвать()
        сам.assertEqual(код, 0, ошибка + вывод)

    def test_индекс_и_рабочие_байты_различаются(сам):
        файл = сам.записать('Данные/текст.md', 'Индекс\n')
        сам.гит('add', '.')
        файл.write_text('Рабочее дерево\n')
        код, вывод, ошибка = сам.вызвать()
        сам.assertEqual(код, 0, ошибка + вывод)
        сам.assertEqual(сам.гит('show', ':Данные/текст.md').decode(), 'Индекс\n')

    def test_удаление_и_переименование(сам):
        файл = сам.записать('Данные/текст.md', 'Текст\n')
        with (сам.корень/сам.запрос).open('a') as поток:
            поток.write('- Удалённый файл: `Данные/текст.md`\n')
        сам.гит('add', '.')
        сам.гит('-c', 'user.name=Тест', '-c', 'user.email=test@example.invalid', 'commit', '-qm', 'Вход')
        файл.unlink()
        код, вывод, ошибка = сам.вызвать()
        сам.assertEqual(код, 0, ошибка + вывод)
        сам.assertEqual(json.loads(вывод)['форматы']['удалено'], 1)
        сам.гит('restore', '--', 'Данные/текст.md')
        сам.гит('mv', 'Данные/текст.md', 'Данные/текст.cjs')
        код, вывод, _ = сам.вызвать()
        сам.assertEqual(код, 1)
        сам.assertIn('Неизвестный формат', вывод)

    def test_ссылка_не_разыменовывается(сам):
        файл = сам.записать('Данные/текст.md', 'Текст\n')
        (сам.корень/'Данные/ссылка.md').symlink_to(файл)
        код, _, _ = сам.вызвать()
        сам.assertEqual(код, 1)
        сам.assertEqual(файл.read_text(), 'Текст\n')

    def test_одинаковый_статус_не_скрывает_дрейф_байтов(сам):
        файл = сам.записать('Данные/текст.md', 'Первый\n')
        def загрузить(имя, путь):
            описание = importlib.util.spec_from_file_location(имя, путь)
            модуль = importlib.util.module_from_spec(описание)
            описание.loader.exec_module(модуль)
            return модуль
        модуль = загрузить('форматы_для_теста', СКРИПТ.with_name('форматы_изменений.py'))
        охват = загрузить('охват_для_теста', СКРИПТ.with_name('сверить-материалы-этапа.py'))
        исходная = модуль.ПРОЕКЦИЯ.классифицировать_содержимое
        def подменить(корень, путь, политика, данные):
            результат = исходная(корень, путь, политика, данные)
            if путь == 'Данные/текст.md':
                файл.write_text('Второй\n')
            return результат
        with patch.object(модуль.ПРОЕКЦИЯ, 'классифицировать_содержимое', side_effect=подменить):
            результат = модуль.проверить(сам.корень, охват)
        сам.assertTrue(any('Байты или режим' in ошибка for ошибка in результат['ошибки']))


if __name__ == '__main__':
    unittest.main()

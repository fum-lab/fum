"""Независимые границы сохранённого JSON; большой исходник не печатается."""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch


КОРЕНЬ = Path(__file__).resolve().parents[1]
СКРИПТ = КОРЕНЬ / 'scripts/компактный_JSON.py'


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def исходное_поведение(каталог):
    """Настоящий RED прежнего прямого просмотра, с долговечным сырым файлом."""
    каталог = Path(каталог)
    данные = json.dumps({'inventory': 'СКРЫТЫЙ_ОРИГИНАЛ_ё😀' * 100000},
                        ensure_ascii=False).encode() + b'\n'
    источник = каталог / 'красный-исходник.json'
    источник.write_bytes(данные)
    os.chmod(источник, 0o600)
    результат = subprocess.run([sys.executable, '-B', '-c',
        'import json,sys; print(json.dumps(json.load(open(sys.argv[1],encoding="utf-8")),ensure_ascii=False))',
        str(источник)], capture_output=True, check=True)
    (каталог / 'красный-прямой-вывод.bin').write_bytes(результат.stdout)
    свидетельство = {'схема': 'fum.красный-прямой-JSON.1', 'бюджет': 4096,
        'исходных_байтов': len(данные), 'raw_sha256': хэш(данные),
        'выдано_байтов': len(результат.stdout), 'stdout_sha256': хэш(результат.stdout),
        'stderr_байтов': len(результат.stderr), 'исходник_неизменён': источник.read_bytes() == данные}
    (каталог / 'красный.json').write_text(json.dumps(свидетельство, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(свидетельство, ensure_ascii=False))
    return 0 if len(результат.stdout) <= 4096 else 1


class КомпактноеЧтение(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        sys.path.insert(0, str(КОРЕНЬ / 'scripts'))
        описание = importlib.util.spec_from_file_location('проверяемый_компактный_JSON', СКРИПТ)
        класс.модуль = importlib.util.module_from_spec(описание)
        sys.modules[описание.name] = класс.модуль
        описание.loader.exec_module(класс.модуль)

    def представить(сам, данные, указатели=None, **пределы):
        return сам.модуль.представить(данные, хэш(данные),
            указатели=[''] if указатели is None else указатели, **пределы)

    def выборка(сам, данные, указатель='', **пределы):
        return json.loads(сам.представить(данные, [указатель], **пределы))['выборки'][0]

    def отказ(сам, данные, причина, **пределы):
        with сам.assertRaises(сам.модуль.ОшибкаПредставления) as пойманная:
            сам.представить(данные, **пределы)
        сам.assertEqual(пойманная.exception.причина, причина)

    def test_гигантский_скаляр_остаётся_метаданными(сам):
        данные = json.dumps({'inventory': 'НЕ_ПОКАЗЫВАТЬ_ё😀' * 100000}, ensure_ascii=False).encode()
        ответ = сам.представить(данные, ['/inventory'], бюджет_байтов=4096)
        сам.assertLessEqual(len(ответ), 4096)
        сам.assertTrue(ответ.endswith(b'\n'))
        сам.assertNotIn('НЕ_ПОКАЗЫВАТЬ'.encode(), ответ)
        запись = json.loads(ответ)['выборки'][0]
        сам.assertFalse(запись['полностью_показано'])
        сам.assertEqual(запись['представление']['указатель'], '/inventory')
        сам.assertEqual(запись['представление']['тип'], 'строка')

    def test_канонический_оракул_и_отдельный_rawSHA(сам):
        данные = br' { "z":1.0, "a":"\u0451" }' + b'\n'
        канон = '{"a":"ё","z":1.0}'.encode()
        запись = сам.выборка(данные)
        сам.assertEqual(запись['sha256'], хэш(канон))
        сам.assertEqual(запись['канонических_байтов'], len(канон))
        сам.assertNotEqual(запись['sha256'], хэш(данные))
        сам.assertEqual(запись['представление']['z']['числовая_лексема'], '1.0')

    def test_исходный_объект_не_подделывает_числовую_замену(сам):
        запись = сам.выборка('[1,{"числовая_лексема":"1","тип":"число"}]'.encode())
        сам.assertEqual(запись['представление'][0], запись['представление'][1])
        сам.assertEqual(запись.get('замены'),
                        [{'указатель': '/0', 'вид': 'числовая-лексема'}])

    def test_числа_не_преобразуются_в_float_или_int(сам):
        лексемы = ['-0', '1', '1.0', '1e0', '1.00e+03', '1e9999', '9' * 6000]
        хэши = []
        for лексема in лексемы:
            запись = сам.выборка(лексема.encode(), скаляр_байтов=10000, бюджет_байтов=16000)
            сам.assertEqual(запись['представление']['числовая_лексема'], лексема)
            сам.assertEqual(запись['sha256'], хэш(лексема.encode()))
            хэши.append(запись['sha256'])
        сам.assertEqual(len(set(хэши)), len(хэши))

    def test_указатели_по_RFC6901(сам):
        данные = b'{"":"empty","a/b":{"~x":["zero","one"]},"~1":"once","01":"object"}'
        for указатель, значение in [('/', 'empty'), ('/a~1b/~0x/1', 'one'),
                                   ('/~01', 'once'),
                                   ('/01', 'object')]:
            сам.assertEqual(сам.выборка(данные, указатель)['представление'], значение)

    def test_отказы_указателей_различимы(сам):
        данные = b'{"a":[0],"s":"scalar"}'
        for указатель, причина in [('a', 'указатель-синтаксис'), ('/~2', 'указатель-синтаксис'),
            ('/a/01', 'указатель-индекс'), ('/a/-', 'указатель-индекс'),
            ('/a/1', 'указатель-не-найден'), ('/unknown', 'указатель-не-найден'),
            ('/s/a', 'указатель-проход')]:
            сам.отказ(данные, причина, указатели=[указатель])

    def test_весь_JSON_строг_даже_в_скрытой_ветви(сам):
        случаи = [(br'{"ok":1,"x":{"a":2,"\u0061":3}}', 'повтор-ключа'),
            (b'{"ok":1,"x":NaN}', 'неконечное-число'),
            (b'{"ok":1,"x":Infinity}', 'неконечное-число'),
            (b'{"ok":1,"x":-Infinity}', 'неконечное-число'),
            (b'{"ok":1', 'JSON'), (b'{"ok":1} true', 'JSON'),
            (br'{"ok":1,"x":"\ud800"}', 'Unicode'),
            (br'{"ok":1,"\udfff":2}', 'Unicode'), (b'"\xff"', 'Unicode')]
        for данные, причина in случаи:
            with сам.subTest(причина=причина):
                сам.отказ(данные, причина, указатели=['/ok'])

    def test_кодировки_кроме_UTF8_не_угадываются(сам):
        сам.отказ('{"x":1}'.encode('utf-16'), 'Unicode')

    def test_парный_surrogate_и_разные_нормализации(сам):
        сам.assertEqual(сам.выборка(br'"\ud83d\ude00"')['представление'], '😀')
        данные = '{"ё":"NFC","ё":"NFD"}'.encode()
        сам.assertEqual(сам.выборка(данные, '/ё')['представление'], 'NFC')
        сам.assertEqual(сам.выборка(данные, '/ё')['представление'], 'NFD')

    def test_независимый_SHA_отвергает_подмену(сам):
        with сам.assertRaises(сам.модуль.ОшибкаПредставления) as пойманная:
            сам.модуль.представить(b'{"a": 1}', хэш(b'{"a":1}'), указатели=[''])
        сам.assertEqual(пойманная.exception.причина, 'sha-источника')

    def test_предел_всего_ответа_с_LF(сам):
        данные = '"ё😀\\n"'.encode()
        ответ = сам.представить(данные)
        сам.assertEqual(сам.представить(данные, бюджет_байтов=len(ответ)), ответ)
        сам.отказ(данные, 'бюджет', бюджет_байтов=len(ответ) - 1)

    def test_ресурсы_отдельно_от_сокращения(сам):
        данные = b'[[0]]'
        сам.представить(данные, предел_глубины=2, предел_элементов=3)
        сам.отказ(данные, 'ресурс-глубины', предел_глубины=1)
        сам.отказ(данные, 'ресурс-элементов', предел_элементов=2)
        сам.отказ(данные, 'ресурс-байтов', предел_входа=len(данные) - 1)
        сам.assertFalse(сам.выборка(данные, глубина=0)['полностью_показано'])
        сам.assertFalse(сам.выборка(b'[0,1]', элементы=1)['полностью_показано'])

    def test_большой_ключ_сворачивает_родителя(сам):
        данные = json.dumps({'НЕ_ПОКАЗЫВАТЬ' * 100000: 1}, ensure_ascii=False).encode()
        запись = сам.выборка(данные)
        сам.assertFalse(запись['полностью_показано'])
        сам.assertEqual(запись['представление']['указатель'], '')
        сам.assertNotIn('НЕ_ПОКАЗЫВАТЬ', json.dumps(запись, ensure_ascii=False))

    def test_bool_и_неизвестный_тип_API_отвергаются(сам):
        for имя in ['бюджет_байтов', 'глубина', 'элементы', 'скаляр_байтов',
                    'предел_входа', 'предел_глубины', 'предел_элементов']:
            сам.отказ(b'null', 'параметры', **{имя: True})
        with сам.assertRaises(сам.модуль.ОшибкаПредставления):
            сам.модуль.представить({'x': 1}, '0' * 64, указатели=[''])

    def командный_вызов(сам, данные, *аргументы):
        with tempfile.TemporaryDirectory() as каталог:
            путь = Path(каталог) / 'исходник.json'
            путь.write_bytes(данные)
            до = путь.stat()
            состав = sorted(Path(каталог).iterdir())
            итог = subprocess.run([sys.executable, '-B', str(СКРИПТ), '--источник', str(путь),
                '--sha256', хэш(данные), '--указатель', '', *аргументы], capture_output=True)
            после = путь.stat()
            сам.assertEqual(путь.read_bytes(), данные)
            сам.assertEqual((до.st_mode, до.st_ino, до.st_mtime_ns),
                            (после.st_mode, после.st_ino, после.st_mtime_ns))
            сам.assertEqual(sorted(Path(каталог).iterdir()), состав)
            сам.assertEqual(итог.stderr, b'')
            return итог

    def test_командный_ответ_и_неизменность(сам):
        итог = сам.командный_вызов(b'{"command":"touch canary","url":"https://example.invalid"}')
        сам.assertEqual(итог.returncode, 0)
        сам.assertTrue(json.loads(итог.stdout)['успех'])

    def test_малый_бюджет_пустые_каналы(сам):
        итог = сам.командный_вызов(b'null', '--бюджет-байтов', '1')
        сам.assertEqual((итог.returncode, итог.stdout, итог.stderr), (2, b'', b''))

    def test_прикреплённый_и_неоднозначный_бюджет(сам):
        for аргументы in [('--бюджет-байтов=1',),
                          ('--бюджет-байтов', '1', '--бюджет-байтов', '1000')]:
            итог = сам.командный_вызов(b'null', *аргументы)
            сам.assertEqual((итог.returncode, итог.stdout, итог.stderr), (2, b'', b''))

    def test_API_ресурсный_отказ_закрыт(сам):
        for стадия, ошибка in [('проверить_глубину', MemoryError),
                              ('канонические_части', RecursionError)]:
            with patch.object(сам.модуль, стадия, side_effect=ошибка):
                сам.отказ(b'null', 'ресурс-парсера')

    def test_ошибка_канала_без_второго_вывода(сам):
        class КаналСОшибкой:
            def fileno(сам):
                raise OSError('недоступный канал')

            @property
            def buffer(сам):
                return сам

            def write(сам, _данные):
                raise OSError('недоступный канал')

        with patch.object(сам.модуль, 'представить_файл', return_value=b'{}\n'), \
             patch.object(sys, 'stdout', КаналСОшибкой()):
            сам.assertEqual(сам.модуль.главная(['--источник', 'x', '--sha256', '0' * 64,
                                              '--указатель', '']), 2)

    def test_дрейф_после_построения_ответа(сам):
        with tempfile.TemporaryDirectory() as каталог:
            путь = Path(каталог) / 'источник.json'
            путь.write_bytes(b'null')

            def изменить(_данные, _хэш, **_параметры):
                путь.write_bytes(b'true')
                return b'{}\n'

            with patch.object(сам.модуль, 'представить', side_effect=изменить):
                with сам.assertRaises(сам.модуль.ОшибкаПредставления) as пойманная:
                    сам.модуль.представить_файл(путь, хэш(b'null'), указатели=[''])
                сам.assertEqual(пойманная.exception.причина, 'дрейф-источника')

    def test_огромная_ошибка_без_утечки(сам):
        for аргументы in [('--неизвестный', 'СЕКРЕТ' * 3000),
                          ('--указатель', '/' + 'СЕКРЕТ' * 3000)]:
            итог = сам.командный_вызов(b'{}', '--бюджет-байтов', '1000', *аргументы)
            сам.assertEqual(итог.returncode, 2)
            сам.assertLessEqual(len(итог.stdout), 1000)
            сам.assertNotIn('СЕКРЕТ'.encode(), итог.stdout)

    def test_недоступный_источник(сам):
        итог = subprocess.run([sys.executable, '-B', str(СКРИПТ), '--источник',
            '/несуществующий-источник', '--sha256', '0' * 64, '--указатель', ''], capture_output=True)
        сам.assertEqual(итог.returncode, 2)
        сам.assertEqual(итог.stderr, b'')
        сам.assertEqual(json.loads(итог.stdout)['причина'], 'источник')


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--исходное-поведение':
        raise SystemExit(исходное_поведение(sys.argv[2]))
    unittest.main()

    def вариант_приёмки(сам, данные):
        # Новый независимый carrier только внутри disposable fixture, без HEAD/ref/index effect.
        def гит_с_входом(аргументы, сырые):
            п = subprocess.run(['git', '-C', str(сам.корень), *аргументы], input=сырые,
                capture_output=True, check=True)
            return п.stdout.decode().strip()
        сырой = байты(данные)

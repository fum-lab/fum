        дерево = гит_с_входом(['mktree'], ('100644 blob ' + объект + '\tproof.json\n').encode())
        коммит = гит_с_входом(['commit-tree', дерево, '-p', сам.носитель, '-m', 'Root proof variant'], b'')
        return сам.селектор(коммит, 'proof.json', сырой)


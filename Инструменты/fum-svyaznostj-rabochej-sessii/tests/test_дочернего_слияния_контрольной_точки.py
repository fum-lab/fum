    def test_импорт_фиксирует_хэш_и_идентичность_двух_исходников_до_первого_чтения(сам):
        м = сам.установщик
        if not hasattr(м, 'ЗАГРУЖЕННОЕ_ДОЧЕРНЕЕ_СОСТОЯНИЕ'):
            сам.fail('RED: отсутствует immutable initial capture дочерних reader/checker pins')
        имя = 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/обычное_поручение.py'
        путь = сам.корень / имя
        зафиксировано = м.ЗАГРУЖЕННОЕ_ДОЧЕРНЕЕ_СОСТОЯНИЕ[имя]
        сам.assertIsNotNone(зафиксировано)
        исходные = путь.read_bytes()
        замена = путь.with_name(путь.name + '.новый-инод')

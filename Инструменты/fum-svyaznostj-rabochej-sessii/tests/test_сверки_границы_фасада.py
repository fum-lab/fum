"""Одна свежая полная область на границу без кэша между операциями."""
import os
from pathlib import Path
import unittest
from unittest import mock

import test_первой_подготовки_открытого_этапа as открытый
import test_создание_коммита as база
from test_план_начала import снимок


class СверкиГраницыФасада(unittest.TestCase):
    def стенд(сам):
        помощник = открытый.ПерваяПодготовкаОткрытогоЭтапа()
        сам.addCleanup(помощник.doCleanups)
        м, р, вход, выбор, _, _ = помощник.открытый_стенд()
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
            план = м.построить_план(вход, выбранный_состав=выбор)
        return м, р, вход, выбор, план

    def test_одна_полная_область_на_границу_без_записей(сам):
        м, р, вход, выбор, план = сам.стенд()
        ж = м._независимый_журнал()
        до = снимок(р.ф.каталог)
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА), \
                mock.patch.object(ж, 'проверить_область_записей',
                    wraps=ж.проверить_область_записей) as область:
            контекст = м._сверить_новую_границу(вход, план, выбор)
        сам.assertEqual(1, область.call_count)
        сам.assertEqual(план['пин_состава'], контекст['пин'])
        сам.assertEqual(до, снимок(р.ф.каталог))

    def test_следующая_граница_перечитывает_выбор_и_контракт(сам):
        for поле in ('выбор', 'контракт'):
            with сам.subTest(поле=поле):
                м, р, вход, выбор, план = сам.стенд()
                with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
                    м._сверить_новую_границу(вход, план, выбор)
                    файл = Path(выбор if поле == 'выбор' else вход['контракт_журнала'])
                    файл.write_bytes(файл.read_bytes() + b'\n')
                    до = снимок(р.ф.каталог)
                    with сам.assertRaisesRegex(ValueError, 'дрейф внешнего S или current contract'):
                        м._сверить_новую_границу(вход, план, выбор)
                сам.assertEqual(до, снимок(р.ф.каталог))

    def test_полная_область_отвергает_запись_вне_T(сам):
        м, р, вход, выбор, план = сам.стенд()
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
            м._сверить_новую_границу(вход, план, выбор)
            чужой = р.ф.корень / 'посторонний.txt'
            чужой.write_bytes(b'outside declared targets\n')
            до = снимок(р.ф.каталог)
            with сам.assertRaisesRegex(ValueError, 'запись вне адресного diff'):
                м._сверить_новую_границу(вход, план, выбор)
        сам.assertEqual(до, снимок(р.ф.каталог))

    def test_модель_проверяется_до_заключительной_полной_области(сам):
        м, р, вход, выбор, план = сам.стенд()
        модель = р.ф.корень / р.п['история_модели']
        модель.write_bytes(модель.read_bytes() + b'\n')
        (р.ф.корень / 'посторонний.txt').write_bytes(b'outside declared targets\n')
        до = снимок(р.ф.каталог)
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА):
            with сам.assertRaisesRegex(ValueError, 'дрейф сохранённой модели или курсора'):
                м._сверить_новую_границу(вход, план, выбор)
        сам.assertEqual(до, снимок(р.ф.каталог))

    def test_планировщик_сохраняет_прежние_два_полных_прохода(сам):
        м, р, вход, выбор, _ = сам.стенд()
        ж = м._независимый_журнал()
        до = снимок(р.ф.каталог)
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=база.ЗАДАЧА), \
                mock.patch.object(ж, 'проверить_область_записей',
                    wraps=ж.проверить_область_записей) as область:
            м.построить_план(вход, выбранный_состав=выбор)
        сам.assertEqual(2, область.call_count)
        сам.assertEqual(до, снимок(р.ф.каталог))

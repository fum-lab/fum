"""Сопоставить подготовку на выросшем источнике с записью и без записи истории."""

import argparse
import hashlib
import json
from pathlib import Path
import statistics
import sys
import time

from test_повторной_подготовки import ПовторнаяПодготовка, основа


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path, required=True)
    аргументы = разбор.parse_args()
    измерения = []
    for повтор in range(3):
        for сохранять in ((False, True) if повтор % 2 == 0 else (True, False)):
            фикстура = ПовторнаяПодготовка()
            try:
                фикстура.setUp()
                фикстура.подготовить_первый()
                фикстура.события.append({'type': 'event_msg', 'payload': {'message': 'x' * (1024 * 1024)}})
                фикстура.записать_источник()
                начало = time.monotonic_ns()
                результат = основа.коммит.подготовить(фикстура.параметры, сохранить_историю=сохранять)
                длительность = time.monotonic_ns() - начало
                байты = фикстура.история.read_bytes()
                подготовка = json.loads(Path(фикстура.параметры['подготовка']).read_text())
                if подготовка['история_sha256'] != hashlib.sha256(байты).hexdigest():
                    raise RuntimeError('подготовка не связана с сохранёнными байтами')
                if сохранять and байты != фикстура.прежние:
                    raise RuntimeError('повтор изменил историю')
                измерения.append({'повтор': повтор + 1, 'сохранить_историю': сохранять,
                    'наносекунды': длительность, 'история_изменена': байты != фикстура.прежние,
                    'курсор_изменён': Path(фикстура.параметры['кэш_модели']).read_bytes() != фикстура.курсор,
                    'размер_источника': фикстура.источник.stat().st_size,
                    'коммит_создан': результат['коммит_создан']})
            finally:
                фикстура.doCleanups()
    данные = {'схема': 'fum.профиль-повторной-подготовки.1', 'измерения': измерения,
        'python': sys.version.split()[0],
        'граница': 'Подготовка целиком с Git-чтением и первичным JSONL; создание фикстуры и первый импорт истории исключены. Основные модули загружены до таймера, ленивый импорт помощника включён в первый повтор. Три пары с чередованием порядка.',
        'медианы_наносекунды': {str(режим): statistics.median(з['наносекунды'] for з in измерения if з['сохранить_историю'] == режим) for режим in (False, True)},
        'sha256': {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in (
            основа.СКРИПТЫ / 'создание_коммита.py', основа.СКРИПТЫ / 'история_модели.py',
            основа.СКРИПТЫ / 'повторная_подготовка_модели.py', Path(__file__),
            Path(__file__).with_name('test_повторной_подготовки.py'))}}
    with аргументы.выход.open('x', encoding='utf-8') as выход:
        json.dump(данные, выход, ensure_ascii=False, indent=2)
        выход.write('\n')


if __name__ == '__main__':
    выполнить()

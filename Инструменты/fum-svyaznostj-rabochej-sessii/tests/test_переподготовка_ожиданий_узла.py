def наблюдать_процесс(модуль, настройки):
    """Только барьеры и остановки вокруг настоящих вызовов; допуск не подменяется."""
    if 'барьер' in настройки:
        исходная = модуль.привязка
        @contextlib.contextmanager
        def привязка(*аргументы, **ключи):
            with исходная(*аргументы, **ключи) as результат:
                Path(настройки['барьер']).write_bytes(b'locked')
                предел = time.monotonic() + 45
                while not Path(настройки['освободить']).exists():
                    if time.monotonic() > предел: raise TimeoutError('барьер не освобождён')
                    time.sleep(0.01)
                yield результат
        модуль.привязка = привязка
    if 'внутренняя_точка' in настройки: внутренний_перерыв(модуль, настройки)
    if 'трасса' not in настройки: return
    события = []
    def учесть(вид, путь):
        события.append({'вид': вид, 'имя': Path(путь).name})
        Path(настройки['трасса']).write_text(json.dumps(события, ensure_ascii=False))
        if len(события) == настройки.get('перерыв'): os._exit(73)
    def обернуть(исходная, вид):
        def действие(путь, *аргументы, **ключи):
            результат = исходная(путь, *аргументы, **ключи)
            учесть(вид, путь)
            return результат
        return действие
    модуль.установить_файл = обернуть(модуль.установить_файл, 'файл и каталог писателя')
    чтение = модуль.коммит.модели.чтение
    чтение._установить = обернуть(чтение._установить, 'файл и каталог истории')
    модели = модуль.коммит.модели
    модели.сохранить_сообщение = обернуть(модели.сохранить_сообщение, 'файл creator')
    исходная = модуль.синхронизировать
    def синхронизировать(пути):
        пути = list(пути)
        результат = исходная(пути)
        учесть('повторная синхронизация файлов и каталогов', пути[0])
        return результат
    модуль.синхронизировать = синхронизировать


def внутренний_перерыв(модуль, настройки):
    цель, точка = настройки['внутренняя_точка']
    текущая = [None]
    исходная = модуль.установить_файл
    def установить(путь, данные, режим):
        имя = None
        if str(путь) == настройки['путь_маркера']:
            имя = 'маркер'
        elif str(путь) == настройки['путь_намерения']:
            значение = json.loads(данные)
            имя = {'переподготовка': 'fence', 'переподготовлено': 'активация',
                'попытка-коммита': 'попытка'}.get(значение.get('стадия'))
        текущая[0] = имя
        try:
            результат = исходная(путь, данные, режим)
            if цель == имя and точка == 'после': os._exit(73)
            return результат
        finally: текущая[0] = None
    модуль.установить_файл = установить
    модели = модуль.коммит.модели
    исходное_сообщение = модели.сохранить_сообщение
    def сообщение(путь, данные):
        имя = ('подготовка' if str(путь) == настройки.get('подготовка') else
            'начальная квитанция' if str(путь) == настройки.get('квитанция') else None)
        текущая[0] = имя
        try:
            результат = исходное_сообщение(путь, данные)
            if цель == имя and точка == 'после': os._exit(73)
            return результат
        finally: текущая[0] = None
    модели.сохранить_сообщение = сообщение
    исходное_открытие = os.open
    def открыть(путь, флаги, *аргументы, **ключи):
        результат = исходное_открытие(путь, флаги, *аргументы, **ключи)
        if текущая[0] == цель == 'подготовка' and точка == 'после открытия' and флаги & os.O_EXCL:
            os._exit(73)
        return результат
    os.open = открыть
    исходная_синхронизация = os.fsync
    def синхронизировать(дескриптор):
        if текущая[0] == цель and точка == 'до file-fsync' and stat.S_ISREG(os.fstat(дескриптор).st_mode):
            os._exit(73)
        return исходная_синхронизация(дескриптор)
    os.fsync = синхронизировать
    исходная_замена = os.replace
    def заменить(*аргументы, **ключи):
        результат = исходная_замена(*аргументы, **ключи)
        if текущая[0] == цель and точка == 'после replace': os._exit(73)
        return результат
    os.replace = заменить
    исходный_гит = модуль.коммит.гит
    def гит(адрес, *аргументы, **ключи):
        результат = исходный_гит(адрес, *аргументы, **ключи)
        if цель == 'Git commit' and аргументы[0] == 'commit': os._exit(73)
        return результат
    модуль.коммит.гит = гит
    чтение = модуль.коммит.сообщения
    исходная_запись = чтение._установить
    def квитанция(путь, данные):
        результат = исходная_запись(путь, данные)
        if str(путь) == настройки.get('квитанция') and цель == 'конечная квитанция' \
                and json.loads(данные).get('состояние') == 'проверен': os._exit(73)
        return результат
    чтение._установить = квитанция


class ПереподготовкаОжиданий(unittest.TestCase):
    def setUp(сам, явные_даты=None):
        сам.с = исходные.ОбновлениеОжиданий()
        сам.с.setUp()
        сам.addCleanup(сам.с.doCleanups)
        if явные_даты is not None:
            среда = patch.dict(os.environ, явные_даты)
            среда.start()
            сам.addCleanup(среда.stop)
        сам.с.назначить_публикуемую_схему()
        сам.с.о.подготовить()
        сам.с.установка()
        сам.старые = {ключ: Path(сам.с.о.параметры[ключ]).read_bytes()
            for ключ in ('сообщение', 'подготовка')}
        сам.цель = сам.с.корень / сам.с.вход['путь']
        сам.байты = сам.цель.read_bytes()
        сам.метка = сам.цель.stat()
        запись = {'type': 'turn_context', 'timestamp': '2026-10-02T00:00:00Z',
            'payload': {'cwd': str(сам.с.корень), 'model': 'gpt-6.1-sol', 'effort': 'ultra'}}
        with сам.с.о.нативный.open('ab') as поток:
            поток.write((json.dumps(запись, ensure_ascii=False) + '\n').encode())
        сам.новые = copy.deepcopy(сам.с.о.параметры)
        for ключ in ('сообщение', 'подготовка', 'квитанция'):
            сам.новые[ключ] = str(сам.с.каталог / ('свежее-' + ключ + '.json'))
        сам.ссылка = сам.с.ссылка_приватная('свежие-параметры.json', сам.новые)
        сам.вход_процесса = сам.с.приватный('вход-процесса.json', сам.с.вход)
        сам.ссылка_процесса = сам.с.приватный('ссылка-процесса.json', сам.ссылка)

    def сверить_сохранённое_основание(сам):
        сам.assertEqual(сам.с.база, сам.с.ф.гит('rev-parse', 'HEAD').strip())
        сам.assertEqual((сам.байты, сам.метка.st_ino, сам.метка.st_mtime_ns),
            (сам.цель.read_bytes(), сам.цель.stat().st_ino, сам.цель.stat().st_mtime_ns))
        сам.assertEqual(сам.старые, {ключ: Path(сам.с.о.параметры[ключ]).read_bytes()
            for ключ in ('сообщение', 'подготовка')})

    def ранний_отказ_идентичности(сам, изменения, *, удалить=(), конфигурация=None):
        with patch.dict(os.environ, изменения):
            for ключ in удалить: os.environ.pop(ключ, None)
            if конфигурация is not None: сам.с.ф.гит('config', *конфигурация)
            до = сам.снимок()
            with patch.object(писатель.коммит, 'подготовить', wraps=писатель.коммит.подготовить) as подготовка:
                with сам.assertRaisesRegex(ValueError, 'identity|явные даты'):
                    писатель.переподготовить(сам.с.вход, сам.ссылка)
                сам.assertEqual(0, подготовка.call_count)
            сам.assertEqual(до, сам.снимок())
            сам.assertFalse((сам.с.каталог / 'переподготовка').exists())
            сам.assertTrue(all(not Path(сам.новые[ключ]).exists()
                for ключ in ('сообщение', 'подготовка', 'квитанция')))
            сам.сверить_сохранённое_основание()


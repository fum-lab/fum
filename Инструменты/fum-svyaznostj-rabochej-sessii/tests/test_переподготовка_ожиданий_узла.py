    def процесс(сам, действие, *добавочные, настройки=None, фоновый=False):
        скрипты = str(Path(писатель.__file__).parent)
        состояние = str(писатель.коммит.готовность.КОРЕНЬ_СОСТОЯНИЯ)
        запуск = ('import sys,json; from pathlib import Path; sys.path.insert(0,sys.argv.pop(1)); '
            'sys.path.insert(0,sys.argv.pop(1)); '
            'import обновление_ожиданий_узла as п; '
            'п.коммит.готовность.КОРЕНЬ_СОСТОЯНИЯ=Path(sys.argv.pop(1)); '
            'import test_переподготовка_ожиданий_узла as т; '
            'т.наблюдать_процесс(п,json.loads(sys.argv.pop(1))); '
            'raise SystemExit(п.главная())')
        настройки_процесса = {'путь_намерения': str(сам.путь_намерения()),
            'путь_маркера': str(сам.с.каталог / 'переподготовка/вызов-подготовки.json'), **(настройки or {})}
        аргументы = [sys.executable, '-B', '-c', запуск, скрипты, str(Path(__file__).parent), состояние,
            json.dumps(настройки_процесса, ensure_ascii=False),
            действие, '--вход', str(сам.вход_процесса), *добавочные]
        if действие == 'переподготовить': аргументы.extend(['--новые-параметры', str(сам.ссылка_процесса)])
        if фоновый:
            return subprocess.Popen(аргументы, cwd=сам.с.корень, stdout=subprocess.PIPE,
                stderr=subprocess.PIPE, text=True)
        return subprocess.run(аргументы, cwd=сам.с.корень, capture_output=True, text=True, timeout=60)


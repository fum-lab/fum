    def гонка(сам, первый, второй, код=0):
        барьер = сам.с.ф.каталог / 'замок-захвачен'
        отпуск = сам.с.ф.каталог / 'освободить-замок'
        добавочные = ('--проверка', исходные.обычная.база.ЗАПУСК) if первый == 'зафиксировать' else ()
        процесс = сам.процесс(первый, *добавочные, фоновый=True,
            настройки={'барьер': str(барьер), 'освободить': str(отпуск)})
        try:
            сам.дождаться_барьера(барьер, процесс)
            отказ = сам.процесс(второй, '--проверка', исходные.обычная.база.ЗАПУСК)
            сам.assertEqual(2, отказ.returncode, отказ.stderr)
            сам.assertIn('другой писатель держит файл', отказ.stderr)
        finally:
            отпуск.write_bytes(b'release')
            вывод, ошибка = процесс.communicate(timeout=60)
        сам.assertEqual(код, процесс.returncode, ошибка)
        return json.loads(вывод) if код == 0 else ошибка


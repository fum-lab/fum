"""Настоящий Creator после возврата исходного каталога; отказы без переноса."""
import fcntl
import hashlib
import json
import os
from pathlib import Path
import stat
import tempfile
import unittest

import test_запуска_принятого_писателя as запуск


class ВозвратRAW(запуск.ЗапускПисателя):
    def setUp(сам):
        super().setUp()
        параметры = json.loads(Path(сам.ф.запрос['новые_параметры']['путь']).read_bytes())
        _, _, _, сам.назначение, сессия = запуск.основа.писатель.коммит.отчёты.разрешить_сессию(
            сам.с.корень, Path(параметры['запрос']))
        сам.назначение.parent.mkdir(parents=True, exist_ok=True)
        if not сам.назначение.exists(): сам.назначение.mkdir(mode=0o755)
        сам.assertFalse(list(сам.назначение.iterdir()))
        сам.источник = сам.с.каталог / 'сохранённый-RAW'
        сам.назначение.rename(сам.источник)
        с = сам.источник.stat()
        ключ = hashlib.sha256((str(сам.с.корень)+'\0'+сессия).encode()).hexdigest()
        сам.замок = Path(tempfile.gettempdir()).resolve() / ('fum-check-runs-'+ключ+'.lock')
        if not сам.замок.exists():
            fd = os.open(сам.замок, os.O_CREAT | os.O_EXCL | os.O_RDWR, 0o600); os.close(fd)
        сам.описание = {'схема': 'fum.возврат-пустого-RAW.1',
            'источник': str(сам.источник), 'назначение': str(сам.назначение),
            'сессия': сессия, 'замок': str(сам.замок),
            'идентичность': {'устройство': с.st_dev, 'инод': с.st_ino,
                'режим': stat.S_IMODE(с.st_mode), 'владелец': с.st_uid}}
        сам.файл_описания = сам.с.приватный('возврат-RAW.json', сам.описание)
        сам.настроить()

    def настроить(сам):
        сам.файл_описания.write_bytes(запуск.байты(сам.описание))
        сам.настройки.update(схема='fum.запуск-принятого-писателя.2',
            возврат_RAW={'путь': str(сам.файл_описания),
                'хэш': запуск.хэш(сам.файл_описания.read_bytes())})
        сам.манифест.write_bytes(запуск.байты(сам.настройки))

    def отказ_без_переноса(сам, ожидается, *, назначение_отсутствует=True):
        до = сам.операция.снимок()
        р = сам.процесс('смена')
        сам.assertNotEqual(0, р.returncode)
        сам.assertIn(ожидается, р.stderr)
        сам.сверить_снимок(до)
        сам.assertTrue(сам.источник.is_dir())
        сам.assertEqual(назначение_отсутствует, not os.path.lexists(сам.назначение))

    def test_полный_Creator_и_повтор_после_возврата(сам):
        super().test_настоящий_Creator_и_RO_повтор_в_разных_процессах()
        с = сам.назначение.stat()
        сам.assertEqual(сам.описание['идентичность'], {'устройство': с.st_dev, 'инод': с.st_ino,
            'режим': stat.S_IMODE(с.st_mode), 'владелец': с.st_uid})
        сам.assertFalse(os.path.lexists(сам.источник))

    def test_иной_инод_не_начинает_подготовку(сам):
        сам.описание['идентичность']['инод'] += 1
        сам.настроить()
        сам.отказ_без_переноса('идентичность сохранённого RAW')

    def test_непустой_источник_не_начинает_подготовку(сам):
        (сам.источник / 'исходник').write_bytes(b'preserved')
        сам.отказ_без_переноса('сохранённый RAW не пуст')

    def test_занятый_замок_не_начинает_подготовку(сам):
        fd = os.open(сам.замок, os.O_RDWR | os.O_NOFOLLOW)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            сам.отказ_без_переноса('другой запуск держит RAW')
        finally:
            fcntl.flock(fd, fcntl.LOCK_UN); os.close(fd)

    def test_существующее_назначение_не_заменяется(сам):
        for вид in ('файл', 'каталог', 'symlink'):
            with сам.subTest(вид=вид):
                if вид == 'файл': сам.назначение.write_bytes(b'preserved destination')
                elif вид == 'каталог': сам.назначение.mkdir()
                else: сам.назначение.symlink_to(сам.источник, target_is_directory=True)
                сам.отказ_без_переноса('символическая ссылка' if вид == 'symlink'
                    else 'назначение RAW уже существует', назначение_отсутствует=False)
                if вид == 'каталог': сам.назначение.rmdir()
                else: сам.назначение.unlink()

    def test_изменённый_descriptor_с_прежним_SHA_не_исполняется(сам):
        сам.файл_описания.write_bytes(сам.файл_описания.read_bytes() + b'\n')
        сам.отказ_без_переноса('подменён descriptor возврата RAW')

    def test_нет_sealed_G2_возврат_запрещён(сам):
        вход = json.loads((сам.Q / запуск.СОСТАВ).read_bytes())['вход']
        (сам.Q / вход).write_text("import обновление_ожиданий_узла as писатель\n"
            "import возврат_RAW_писателя as возврат\n"
            "параметры = писатель.канон.разобрать(писатель.приватная_ссылка(настройки['новые_параметры']))\n"
            "возврат.вернуть(U, параметры, настройки['новые_параметры'], описание_возврата, {}, сверить_эффект)\n")
        сам.гит('add', вход); сам.гит('commit', '-qm', 'Открытая попытка возврата до seal')
        сам.q = сам.гит('rev-parse', 'HEAD').strip()
        сам.настройки['код']['коммит'] = сам.q
        сам.манифест.write_bytes(запуск.байты(сам.настройки))
        сам.отказ_без_переноса('нет genuine sealed G2')

    def test_null_descriptor_не_пропускает_возврат(сам):
        сам.описание = None
        сам.настроить()
        сам.отказ_без_переноса('описание возврата RAW не объект')


def load_tests(loader, tests, pattern):
    имена = ('test_полный_Creator_и_повтор_после_возврата',
        'test_иной_инод_не_начинает_подготовку', 'test_непустой_источник_не_начинает_подготовку',
        'test_занятый_замок_не_начинает_подготовку', 'test_существующее_назначение_не_заменяется',
        'test_изменённый_descriptor_с_прежним_SHA_не_исполняется', 'test_нет_sealed_G2_возврат_запрещён',
        'test_null_descriptor_не_пропускает_возврат')
    return unittest.TestSuite(ВозвратRAW(имя) for имя in имена)

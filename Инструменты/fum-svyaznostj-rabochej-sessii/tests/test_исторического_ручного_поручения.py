def вход_до_акта(ф):
    решение = copy.deepcopy(ф.решение)
    решение['акт']['путь'] = 'Планирование/поручения/будущий-исторический-акт.json'
    ф.решение = решение
    ф.вход['решение'] = ф.сохранить('Планирование/решение-истории.json',г.байты(решение))
    запрос = ф.ф.корень/ф.новый; отчёт = запрос.with_name('отчёт.md')
    обёртка = г.этап.коммит.отчёты
    with contextlib.redirect_stdout(io.StringIO()):
        код = обёртка.выполнить_запуск(ф.ф.корень,запрос,'Проверить пару до ACT','Фикстура',None,15,
            [sys.executable,'-B','-c','pass'],класс_проверки='адресная',приёмочные_раунды=True)
    if код:
        raise ValueError('Не выполнена подготовительная проверка пары')
    новые = обёртка.прочитать_историю_проверок(обёртка.разрешить_сессию(ф.ф.корень,запрос)[3],ф.новый)
    цели = list(dict.fromkeys([*решение['подготовка']['исполнитель']['цели'],ф.новый,
        str(Path(ф.новый).with_name('отчёт.md')),*[п.relative_to(ф.ф.корень).as_posix() for п,_,_ in новые]]))
    наполнение = {'задача':решение['координатор'],'запрос':ф.новый,'ожидаемые_цели':[],
        **решение['подготовка']['исполнитель']['наполнение']}
    пара = г.рендер.сформировать(запрос.read_bytes(),отчёт.read_bytes(),наполнение,цели,
        [(п.relative_to(ф.ф.корень).as_posix(),з,б) for п,з,б in новые],
        г.этап.коммит.отчёты,{п:{'тип':'файл'} for п in цели})
    запрос.write_bytes(пара[0]); отчёт.write_bytes(пара[1])
    with contextlib.redirect_stdout(io.StringIO()):
        г.этап.коммит.отчёты.выполнить_предпросмотр(ф.ф.корень,запрос)
    ф.вход['снимок'] = г.собственное_дерево(ф.вход)[1]
    return {**{к:з for к,з in ф.вход.items() if к!='выбор_акта'},
        'схема':'fum.предпроверка-исторического-поручения.1','фаза':'предпроверка'}



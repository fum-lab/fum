"""Полнота исходных сообщений независимо от курсора и похожести текста."""
import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from unittest import mock
from pathlib import Path


ПУТЬ = Path(__file__).resolve().parents[1] / "scripts" / "сообщения_задачи.py"
СПЕЦИФИКАЦИЯ = importlib.util.spec_from_file_location("сообщения_задачи", ПУТЬ)
МОДУЛЬ = importlib.util.module_from_spec(СПЕЦИФИКАЦИЯ)
СПЕЦИФИКАЦИЯ.loader.exec_module(МОДУЛЬ)
ЗАДАЧА = "00000000-0000-0000-0000-000000000177"


def строка(значение):
    return (json.dumps(значение, ensure_ascii=False) + "\n").encode()


def сообщение(текст, номер, *, виды=None, части=None):
    return {"type": "response_item", "payload": {
        "type": "message", "role": "user", "id": f"msg_{номер}",
        "content": части if части is not None else [{"type": "input_text", "text": текст}],
        "internal_chat_message_metadata_passthrough": {
            "content_item_kinds": ["user.text"] if виды is None else виды}}}


class ПроверкаСообщенийЗадачи(unittest.TestCase):
    def setUp(проверка):
        проверка.временный = tempfile.TemporaryDirectory()
        проверка.addCleanup(проверка.временный.cleanup)
        проверка.корень = Path(проверка.временный.name) / "проект"
        проверка.корень.mkdir()
        проверка.исходник = Path(проверка.временный.name) / "диалог.jsonl"
        проверка.кэш = Path(проверка.временный.name) / "кэш.json"
        проверка.заголовок = строка({"type": "session_meta", "payload": {"id": ЗАДАЧА}})
        проверка.исходник.write_bytes(проверка.заголовок)

    def добавить(проверка, *записи):
        with проверка.исходник.open("ab") as поток:
            for запись in записи:
                поток.write(строка(запись))

    def прочитать(проверка, **параметры):
        return МОДУЛЬ.прочитать_сообщения(
            проверка.исходник, ЗАДАЧА, корень_репозитория=проверка.корень,
            кэш=проверка.кэш, **параметры)

    def test_старый_экземпляр_сохраняется_после_курсора_и_повтора(проверка):
        проверка.добавить(сообщение("Продолжай.\n", 1))
        первый = проверка.прочитать()
        проверка.добавить(сообщение("Продолжай.\n", 2), сообщение("Сначала проверь.\n", 3))
        второй = проверка.прочитать()
        проверка.assertEqual(len(второй["сообщения"]), 3)
        проверка.assertEqual(второй["сообщения"][0], первый["сообщения"][0])
        проверка.assertNotEqual(второй["сообщения"][0]["экземпляр"], второй["сообщения"][1]["экземпляр"])

    def test_транспортный_дубль_не_новая_команда(проверка):
        запись = сообщение("Сделай.", 1)
        проверка.добавить(запись, {"type": "event_msg", "payload": {"type": "user_message", "message": "Сделай."}},
                     dict(запись, timestamp="другая транспортная метка"))
        снимок = проверка.прочитать()
        проверка.assertEqual(len(снимок["сообщения"]), 1)
        проверка.assertEqual(len(снимок["сообщения"][0]["дубли"]), 1)

    def test_один_транспортный_идентификатор_с_разными_байтами_отклоняется(проверка):
        проверка.добавить(сообщение("Сделай.", 1), сообщение("Отмени.", 1))
        with проверка.assertRaisesRegex(МОДУЛЬ.ОшибкаСообщений, "транспорт"):
            проверка.прочитать()

    def test_многочастное_содержимое_и_неоднозначность_сохраняются(проверка):
        части = [{"type": "input_text", "text": "Разбери"},
                 {"type": "input_image", "image_url": "opaque:fixture", "detail": "original"},
                 {"type": "input_text", "text": " полностью.\n"}]
        проверка.добавить(сообщение(None, 1, виды=["user.text", "user.image", "user.text"], части=части),
                     сообщение("Не угадывай происхождение.", 2, виды=["unknown"]))
        снимок = проверка.прочитать()
        проверка.assertEqual(снимок["сообщения"][0]["содержимое"], части)
        проверка.assertEqual(снимок["сообщения"][1]["происхождение"], "неоднозначный")
        проверка.assertFalse(снимок["полнота_подтверждена"])

    def test_неполный_хвост_не_теряется_после_дописывания(проверка):
        часть = строка(сообщение("Последнее сообщение.", 1))
        проверка.исходник.write_bytes(проверка.заголовок + часть[:-5])
        первый = проверка.прочитать()
        проверка.assertEqual(первый["сообщения"], [])
        проверка.assertGreater(первый["неполный_хвост"], 0)
        проверка.assertFalse(первый["полнота_подтверждена"])
        with проверка.исходник.open("ab") as поток:
            поток.write(часть[-5:])
        проверка.assertEqual(len(проверка.прочитать()["сообщения"]), 1)

    def test_изменение_старого_префикса_при_добавлении_хвоста_обнаруживается(проверка):
        проверка.добавить(сообщение("Разрешено.", 1))
        проверка.прочитать()
        проверка.исходник.write_bytes(проверка.исходник.read_bytes().replace("Разрешено".encode(), "Запрещено".encode()) + строка(сообщение("Новое.", 2)))
        with проверка.assertRaisesRegex(МОДУЛЬ.ОшибкаСообщений, "префикс"):
            проверка.прочитать()

    def test_усечение_и_чужая_задача_не_пустой_остаток(проверка):
        проверка.добавить(сообщение("Сделай.", 1))
        проверка.прочитать()
        проверка.исходник.write_bytes(проверка.заголовок)
        with проверка.assertRaises(МОДУЛЬ.ОшибкаСообщений):
            проверка.прочитать()
        проверка.кэш.unlink()
        проверка.исходник.write_bytes(строка({"type": "session_meta", "payload": {"id": "чужая"}}))
        with проверка.assertRaises(МОДУЛЬ.ОшибкаСообщений):
            проверка.прочитать()

    def test_недоступность_повторные_ключи_и_символическая_ссылка_отклоняются(проверка):
        проверка.исходник.unlink()
        with проверка.assertRaises(МОДУЛЬ.ОшибкаСообщений):
            проверка.прочитать()
        проверка.исходник.write_bytes(проверка.заголовок + b'{"type":"event_msg","type":"response_item"}\n')
        with проверка.assertRaises(МОДУЛЬ.ОшибкаСообщений):
            проверка.прочитать()
        цель = проверка.исходник.with_suffix(".другое")
        проверка.исходник.rename(цель)
        проверка.исходник.symlink_to(цель)
        with проверка.assertRaises(МОДУЛЬ.ОшибкаСообщений):
            проверка.прочитать()

    def test_приватный_кэш_не_попадает_в_рабочее_дерево(проверка):
        проверка.кэш = проверка.корень / "приватный.json"

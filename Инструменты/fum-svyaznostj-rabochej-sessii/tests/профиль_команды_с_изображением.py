"""Парный профиль прежнего текстового допуска и новой текстовой проекции."""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import statistics
import time

import test_команды_с_изображением as проверка


def измерить(параметры):
    начало = time.perf_counter_ns()
    результат = проверка.база.коммит.команды(параметры)
    return {'длительность_нс': time.perf_counter_ns() - начало,
        'результат_sha256': hashlib.sha256(проверка.база.коммит.байты(результат)).hexdigest()}


def выполнить(выход):
    if выход.exists():
        raise ValueError('Выход уже существует')
    фикстура = проверка.КомандыСИзображением()
    фикстура.setUp()
    try:
        фикстура.настроить([{'type': 'input_text', 'text': 'Открытый текст ё\n' * 4096}])
        новые = copy.deepcopy(фикстура.ф.параметры)
        кэш = фикстура.ф.каталог / 'кэш-профиля.json'
        снимок = проверка.база.прочитать_сообщения(фикстура.ф.источник, проверка.база.ЗАДАЧА,
            корень_репозитория=фикстура.ф.корень, кэш=кэш)
        новые['источники'][0]['кэш'] = str(кэш)
        прежние = copy.deepcopy(новые)
        прежние['схема'] = 'fum.создание-коммита.5'
        до = фикстура.ф.источник.read_bytes()
        прогрев = {'прежний': измерить(прежние), 'новый': измерить(новые)}
        пары = []
        for номер in range(5):
            порядок = [('прежний', прежние), ('новый', новые)]
            if номер % 2:
                порядок.reverse()
            пара = {имя: измерить(вход) for имя, вход in порядок}
            assert пара['прежний']['результат_sha256'] == пара['новый']['результат_sha256']
            пары.append(пара)
        assert до == фикстура.ф.источник.read_bytes()
        текстовый_вход = {'байты': len(до), 'sha256': снимок['sha256']}
        фикстура.настроить()
        фикстура.ф.события[-1]['payload']['content'][2]['image_url'] = 'data:image/png;base64,' + 'AAAA' * 262144
        фикстура.настроить(фикстура.ф.события[-1]['payload']['content'])
        до = фикстура.ф.источник.read_bytes()
        изображения = [измерить(фикстура.ф.параметры) for _ in range(3)]
        assert до == фикстура.ф.источник.read_bytes()
        медианы = {имя: statistics.median(п[имя]['длительность_нс'] for п in пары) for имя in ('прежний', 'новый')}
        код = {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in (
            Path(проверка.база.коммит.__file__), Path(проверка.база.коммит.готовность.__file__),
            Path(проверка.база.СКРИПТЫ / 'текст_команды_с_изображением.py'), Path(__file__))}
        результат = {'схема': 'fum.профиль-команды-с-изображением.1', 'код': код,
            'граница': 'API команды на синтетическом нативном источнике; пары .5/.6 одного текста с проверенным кэшем. Прежняя ветвь сохранена в текущем коде. Git, модель, подготовка корпуса и Desktop исключены.',
            'вход_текста': текстовый_вход, 'прогрев': прогрев, 'пары': пары, 'медианы_нс': медианы,
            'изображение': {'байты_источника': len(до), 'sha256': hashlib.sha256(до).hexdigest(), 'замеры': изображения},
            'решение': 'Линейная проверка формы base64 и точного снимка сохраняется; декодирование изображения не нужно для текстовой проекции. Новый постоянный кэш не оправдан этим ограниченным профилем. Ускорение полного цикла не заявляется.'}
        with os.fdopen(os.open(выход, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), 'w') as поток:
            json.dump(результат, поток, ensure_ascii=False, indent=2)
            поток.write('\n')
        print(json.dumps(результат, ensure_ascii=False))
    finally:
        фикстура.doCleanups()


if __name__ == '__main__':
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path, required=True)
    выполнить(разбор.parse_args().выход)

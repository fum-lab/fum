class ПотеряннаяКвитанция:
    """Только подтверждение теряется; первая настоящая запись контейнера завершается."""
    def __init__(сам, контейнер):
        сам.контейнер = контейнер
        сам.первый = True
        сам.попытки = 0

    def сохранить(сам, описание, данные):
        сам.попытки += 1
        ответ = сам.контейнер.сохранить(описание, данные)
        if сам.первый:
            сам.первый = False
            raise OSError("синтетическая потеря уже полученной квитанции")
        return ответ

    def извлечь(сам, идентификатор):
        return сам.контейнер.извлечь(идентификатор)


def рабочий_процесс(путь):
    запуск = time.monotonic_ns() - НАЧАЛО_ЗАПУСКА
    вход = json.loads(путь.read_bytes())
    контейнер = состояние.КонтейнерПроцессов(корень_данных=Path(вход["контейнер"]),
        писатель=вход["писатель"], читатель=вход["читатель"], корень_репозитория=Path(вход["корень"]))
    потеря = ПотеряннаяКвитанция(контейнер)
    tracemalloc.start()
    начало = time.monotonic_ns()
    цикл = состояние.ЦиклНаблюдения(вход["доверие"], корень=Path(вход["корень"]), контейнер=потеря,
        история=вход["история"])
    инициализация = time.monotonic_ns() - начало
    полные_байты = состояние.прочитать_файл(Path(вход["ответ"]), предел=состояние.ПРЕДЕЛ)
    первый = цикл.наблюдать(lambda запрос: полные_байты, источник="синтетическая профильная фикстура; не MCP")
    assert первый["наблюдения"][0]["состояние"] == "доставка unknown"
    итог = цикл.повторить_доставку(первый["наблюдения"][0]["задача"])
    _, пик = tracemalloc.get_traced_memory(); tracemalloc.stop()
    assert итог["поколение_актуально"] and not итог["допуск_эффекта"]
    assert итог["профиль"]["вызовов_читающего_адаптера"] == 1 and потеря.попытки == 2
    assert итог["профиль"]["send"] == итог["профиль"]["create"] == 0
    assert итог["профиль"]["контейнер_наносекунды"] > 0 and итог["профиль"]["извлечение_наносекунды"] > 0
    assert all(not наблюдение_истории["свежее_в_этом_цикле"] for наблюдение_истории in итог["история"])
    память_процесса = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    измерения = {**итог["профиль"], "импорт_модулей_наносекунды": запуск,
        "инициализация_наносекунды": инициализация, "пик_python_байтов": пик,
        "пик_RSS_процесса_байтов": память_процесса if sys.platform == "darwin" else память_процесса * 1024,
        "попыток_контейнера": потеря.попытки, "задержка_фикстуры_наносекунды": итог["профиль"]["mcp_наносекунды"]}
    del измерения["mcp_наносекунды"]
    return {"измерения": измерения, "наблюдения": итог["наблюдения"], "цикл": итог["цикл"],
        "ожидания_sha256": hashlib.sha256(состояние.кодировать(итог["ожидания"])).hexdigest()}


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path)
    разбор.add_argument("--повторы", type=int, default=3)
    разбор.add_argument("--рабочий", type=Path)
    параметры = разбор.parse_args()
    if параметры.рабочий:
        sys.stdout.buffer.write(состояние.кодировать(рабочий_процесс(параметры.рабочий)))
        return
    if параметры.выход is None or not 3 <= параметры.повторы <= 10:
        разбор.error("нужны --выход и от 3 до 10 повторов")
    двоичные = Path(os.environ["FUM_TEST_BIN_DIR"]).resolve()
    навык = Path(__file__).resolve().parents[1]
    репозиторий = навык.parents[1]
    исходники = [Path(__file__).resolve(), навык / "scripts/состояние_задач_узла.py",
        навык / "scripts/восстановление_прерванной_задачи.py", навык / "scripts/компактный_ответ_задачи.py",
        Path(__file__).with_name("test_состояние_задач_узла.py"),
        репозиторий / "Приложения/FUMA/Packages/КонтейнерНаблюдений/Sources/ПисательКонтейнера/main.swift"]
    хэши = {str(п.relative_to(репозиторий)): hashlib.sha256(п.read_bytes()).hexdigest() for п in исходники}
    пример = ЦиклКонтроллера(); пример.подготовить_испытание()
    try:
        папка = Path(пример.временное_окружение.name).resolve()
        контейнер = папка / "контейнер"; контейнер.mkdir(mode=0o700)
        ответ = папка / "ответ.json"; ответ.write_bytes(байты(пример.ответ()))
        до = гит(пример.с.репо, "status", "--porcelain"), гит(пример.с.репо, "show-ref")
        наблюдения, замеры, циклы = [], [], []
        эталон = None
        for номер in range(параметры.повторы):
            вход = {"доверие": пример.доверие, "корень": str(пример.с.репо), "контейнер": str(контейнер),
                "писатель": str(двоичные / "писатель-контейнера"), "читатель": str(двоичные / "читатель-контейнера"),
                "ответ": str(ответ), "история": наблюдения}
            путь = папка / ("вход-" + str(номер) + ".json"); путь.write_bytes(байты(вход))
            начало = time.monotonic_ns()
            процесс = subprocess.run([sys.executable, "-B", str(Path(__file__).resolve()), "--рабочий", str(путь)],
                stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=120, check=True)
            общее = time.monotonic_ns() - начало
            итог = json.loads(процесс.stdout)
            if эталон is None: эталон = итог["ожидания_sha256"]
            assert итог["ожидания_sha256"] == эталон
            assert итог["цикл"] not in циклы
            циклы.append(итог["цикл"])
            наблюдения.extend(итог["наблюдения"])
            замеры.append({**итог["измерения"], "новый_процесс_всего_наносекунды": общее,
                "исторических_наблюдений": номер})
        assert до == (гит(пример.с.репо, "status", "--porcelain"), гит(пример.с.репо, "show-ref"))
        assert хэши == {str(п.relative_to(репозиторий)): hashlib.sha256(п.read_bytes()).hexdigest() for п in исходники}
        результат = {"схема": "fum.профиль-состояния-задач-узла.1", "повторы": параметры.повторы,
            "замеры": замеры, "медианы": {ключ: statistics.median(з[ключ] for з in замеры) for ключ in замеры[0]},
            "исходники_sha256": хэши, "expected_sha256": эталон, "expected_и_refs_не_изменены": True,
            "MCP_задержка": "unknown; внешнее живое чтение измеряется отдельно",
            "граница": "Новые процессы контроллера и реальные Swift-процессы контейнера; читающий адаптер синтетический. Установка Git-фикстуры исключена. Время импорта не включает запуск интерпретатора; wall процесса включает всё. Вложенные фазы не суммируются с общим временем. tracemalloc учитывает Python; RSS относится к процессу контроллера, память Swift/Git unknown. I/O не объявляется холодным. Потеря квитанции имитируется после успешной записи и fsync; повтор доставки использует прежние bytes/описание, API не повторяется. Это не падение питания или ОС.",
            "решение_об_оптимизации": "Сохранить повторное чтение Git и проверку exact extraction. На конечном входе нет доказательства пользы кэша с теми же гарантиями актуальности; общее ускорение FUM не заявлено."}
        параметры.выход.parent.mkdir(parents=True, exist_ok=True)
        with параметры.выход.open("xb") as поток: поток.write(байты(результат))
        print(json.dumps({"схема": результат["схема"], "повторы": параметры.повторы, "медианы": результат["медианы"]}, ensure_ascii=False))
    finally:
        пример.doCleanups()


if __name__ == "__main__":
    выполнить()

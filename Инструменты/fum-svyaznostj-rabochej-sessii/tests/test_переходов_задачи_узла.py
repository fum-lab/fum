import выбор_ожиданий_узла as выбор


class ФикстураПереходов:
    def __init__(сам, папка):
        сам.с = Сценарий(папка)
        сам.с.вход['исполнители'][0]['снимок'] = None
        сам.решение = copy.deepcopy(сам.с.решение)
        сам.решение['ход'] = None
        сам.ид = dict(узел='узел-1', репозиторий='репозиторий-1', координатор=КООРДИНАТОР,
            владелец=ДОЧЬ, поколение_полномочий='поколение-1')
        старый = {'схема': 'fum.ожидаемое-состояние-узла.1', **сам.ид,
            'основание': сам.с.постановка, 'предпросмотр': сам.с.вход}
        источник = сам.с.сохранить('expected.json', байты(старый))
        гит(сам.с.репо, 'branch', 'codex/узел', источник['коммит'])
        гит(сам.с.репо, 'switch', '-c', 'codex/задача')
        сам.вход = {'схема': 'fum.цепочка-переходов-задачи-узла.1',
            'доверие': {'схема': 'fum.доверие-ожиданиям-узла.1', **сам.ид,
                'ref': 'refs/heads/codex/узел', 'источник': источник},
            'постановка_выбора': сам.с.постановка, 'переходы': [],
            'выбранное': None, 'позднее_управление': []}
        сам.переход()

    def переход(сам, *, поздний=False, **поля):
        сам.решение.update(поля)
        сам.решение['событие'] = 'переход-' + str(len(сам.вход['переходы']) + len(сам.вход['позднее_управление']))
        источник = сам.с.сохранить('переход.json', байты(сам.решение))
        список = сам.вход['позднее_управление'] if поздний else сам.вход['переходы']
        предыдущий = (сам.вход['позднее_управление'] or сам.вход['переходы'])[-1]['источник'] if сам.вход['переходы'] else None
        список.append({'источник': источник, 'предыдущий': предыдущий, 'основание': сам.с.постановка})
        if not поздний: сам.вход['выбранное'] = источник
        return источник

    def снимок(сам):
        return {str(п.relative_to(сам.с.репо)): хэш(п.read_bytes())
            for п in сам.с.репо.rglob('*') if п.is_file()}

    def состав(сам):
        сам.переход(состояние='пауза', ожидание='Согласованная пауза')
        сам.переход(состояние='открыт', ожидание=None)
        готовое = сам.с.сохранить('готовый.md', b'reviewable result\n')
        сам.переход(результат={'состояние': 'готов', 'источник': готовое})
        сам.переход(поручение=сам.с.акт(ДОЧЬ), этап='доработка-v2', результат=None)
        сам.переход(результат={'состояние': 'готов', 'источник': готовое})
        сам.переход(состояние='закрыт', результат={'состояние': 'принят', 'источник': готовое})


class ПроверкиПереходов(unittest.TestCase):
    def setUp(сам):
        временное = tempfile.TemporaryDirectory(prefix='fum-task-transitions-')
        сам.addCleanup(временное.cleanup)
        сам.ф = ФикстураПереходов(временное.name)
        сам.м = importlib.import_module('переходы_задачи_узла')

    def построить(сам):
        return сам.м.построить(сам.ф.вход, корень=сам.ф.с.репо)

    def test_полная_явная_цепочка_и_прежний_формат(сам):
        сам.ф.состав(); до = сам.ф.снимок(); итог = сам.построить()
        ручной = выбор.построить({'схема': 'fum.выбор-ожиданий-узла.1',
            'доверие': сам.ф.вход['доверие'], 'постановка_выбора': сам.ф.с.постановка,
            'решения': [сам.ф.вход['выбранное']]}, корень=сам.ф.с.репо)
        сам.assertEqual(итог['кандидат'], ручной['кандидат'])
        сам.assertEqual(итог['предпросмотр']['исполнители'][0]['этап'], 'закрыт')
        сам.assertFalse(итог['допуск_эффекта']); сам.assertEqual(до, сам.ф.снимок())
        сам.assertFalse(json.loads(итог['кандидат'])['предпросмотр']['полнота_перечня'])

    def test_пауза_и_отмена_позже_открытого_выбора(сам):
        for состояние in ['пауза', 'отменён']:
            with сам.subTest(состояние=состояние):
                сам.ф.вход['позднее_управление'] = []
                сам.ф.переход(поздний=True, состояние=состояние, ожидание='Тестовая поздняя команда')
                итог = сам.построить()
                сам.assertEqual(итог['предпросмотр']['действие']['вид'], 'ожидание')
                сам.assertEqual(итог['предпросмотр']['исполнители'][0]['этап'], состояние)
                сам.assertNotEqual(итог['эффективное'], итог['выбранное'])

    def test_неизвестный_исход_не_исчезает_при_смене_акт_и_события(сам):
        сам.ф.переход(эффекты={'отправка': 'unknown', 'репозиторий': 'не было'})
        сам.assertEqual(сам.построить()['предпросмотр']['действие']['вид'], 'адресная сверка')
        сам.ф.переход(поручение=сам.ф.с.акт(ДОЧЬ), этап='новый-v2',
            эффекты={'отправка': 'не было', 'репозиторий': 'не было'})
        with сам.assertRaisesRegex(ValueError, 'unknown'): сам.построить()

    def test_чужой_владелец_и_акт(сам):
        оригинал = copy.deepcopy(сам.ф.решение)
        for правка in [{'владелец': ДРУГАЯ}, {'поручение': сам.ф.с.акт(ДРУГАЯ)}]:
            сам.ф.решение = copy.deepcopy(оригинал)
            сам.ф.вход['переходы'] = []; сам.ф.переход(**правка)
            with сам.assertRaises(ValueError): сам.построить()

    def test_каждый_акт_проверяется_а_не_только_последний(сам):
        акт = copy.deepcopy(сам.ф.решение['поручение'])
        данные = json.loads(сам.ф.с.решение['поручение'] and
            гит(сам.ф.с.репо, 'show', акт['коммит'] + ':' + акт['путь']))
        данные['исполнитель'] = ДРУГАЯ
        неверный = {**сам.ф.с.сохранить('неверный-ACT.json', байты(данные)),
            'координатор': КООРДИНАТОР, 'исполнитель': ДОЧЬ}
        сам.ф.переход(поручение=неверный, этап='промежуточный-v2')
        сам.ф.переход(поручение=сам.ф.с.акт(ДОЧЬ), этап='последний-v3')
        for запись in сам.ф.вход['переходы']:
            источник = запись['источник']
            сам.assertEqual(источник['sha256'], хэш(гит(сам.ф.с.репо, 'show',
                источник['коммит'] + ':' + источник['путь']).encode() + b'\n'))
        with сам.assertRaises(ValueError): сам.построить()

    def test_перестановка_селекторов_отдельно(сам):
        сам.ф.переход(состояние='пауза'); сам.ф.переход(состояние='открыт')
        сам.ф.вход['переходы'][0], сам.ф.вход['переходы'][1] = сам.ф.вход['переходы'][1], сам.ф.вход['переходы'][0]
        with сам.assertRaises(ValueError): сам.построить()

    def test_дублирование_селекторов_отдельно(сам):
        запись = copy.deepcopy(сам.ф.вход['переходы'][0])
        запись['предыдущий'] = copy.deepcopy(запись['источник'])
        сам.ф.вход['переходы'].append(запись)
        with сам.assertRaisesRegex(ValueError, 'повтор выбранного selector'): сам.построить()

    def test_сдвиг_ветки_и_поколения_отклоняется(сам):
        гит(сам.ф.с.репо, 'update-ref', сам.ф.вход['доверие']['ref'], сам.ф.вход['выбранное']['коммит'])
        with сам.assertRaises(ValueError): сам.построить()

    def test_соседняя_вершина_не_подменяет_выбор(сам):
        первый = сам.построить()
        сам.ф.с.сохранить('сосед.json', байты({**сам.ф.решение, 'состояние': 'пауза'}))
        сам.assertEqual(первый['кандидат'], сам.построить()['кандидат'])

    def test_закрытый_этап_не_открывается_тем_же_акт(сам):
        сам.ф.переход(состояние='закрыт'); сам.ф.переход(состояние='открыт')
        with сам.assertRaises(ValueError): сам.построить()

    def test_передача_на_ревью_открыта_и_не_доказывает_получение(сам):
        источник = сам.ф.с.сохранить('готовый.md', b'review\n')
        сам.ф.переход(результат={'состояние': 'готов', 'источник': источник})
        итог = сам.построить(); актёр = json.loads(итог['кандидат'])['предпросмотр']['исполнители'][0]
        сам.assertEqual(итог['предпросмотр']['исполнители'][0]['этап'], 'открыт')
        сам.assertIsNone(актёр['доставка']); сам.assertIsNone(актёр['снимок'])
        сам.assertFalse(итог['предпросмотр']['завершение_всей_работы_доказано'])
        сам.ф.переход(результат=None)
        with сам.assertRaises(ValueError): сам.построить()

    def test_повреждённый_хэш_отсутствующий_объект_лишнее_поле(сам):
        исходный = copy.deepcopy(сам.ф.вход)
        for правка in ['sha256', 'путь', 'лишнее']:
            сам.ф.вход = copy.deepcopy(исходный)
            if правка == 'лишнее': сам.ф.вход[правка] = None
            else: сам.ф.вход['переходы'][0]['источник'][правка] = '0' * 64 if правка == 'sha256' else 'нет.json'
            with сам.assertRaises(ValueError): сам.построить()

    def test_два_процесса_офлайн_повторные_ключи_и_грязные_файлы(сам):
        сам.ф.состав(); файл = сам.ф.с.папка/'вход.json'; файл.write_bytes(байты(сам.ф.вход)); файл.chmod(0o600)
        (сам.ф.с.репо/'переход.json').write_text('Незакоммиченная работа неизвестна')
        до = сам.ф.снимок()
        команда = [sys.executable, '-B', str(Path(сам.м.__file__)), '--корень-репозитория', str(сам.ф.с.репо), '--вход', str(файл)]
        ответы = [subprocess.run(команда, capture_output=True, check=True) for _ in range(2)]
        сам.assertEqual(ответы[0].stdout, ответы[1].stdout); сам.assertEqual(до, сам.ф.снимок())
        итог = json.loads(ответы[0].stdout)
        сам.assertEqual(итог['границы']['runtime'], 'unknown')
        файл.write_bytes(b'{"x":1,"x":2}')
        отказ = subprocess.run(команда, capture_output=True)
        сам.assertEqual(отказ.returncode, 1); сам.assertEqual(отказ.stdout, b'')

    def test_пауза_из_соседней_ветки_не_требует_родства(сам):
        выбранное = сам.ф.вход['выбранное']
        гит(сам.ф.с.репо, 'switch', '-c', 'codex/управление', сам.ф.с.постановка['коммит'])
        сам.ф.переход(поздний=True, состояние='пауза')
        пауза = сам.ф.вход['позднее_управление'][0]['источник']['коммит']
        родство = subprocess.run(['git', '-C', str(сам.ф.с.репо), 'merge-base',
            '--is-ancestor', выбранное['коммит'], пауза], capture_output=True)
        сам.assertEqual(родство.returncode, 1)
        сам.assertEqual(сам.построить()['предпросмотр']['действие']['вид'], 'ожидание')

    def test_исторический_снимок_не_становится_текущим_наблюдением(сам):
        снимок = сам.ф.с.снимок(ДОЧЬ, статус='active')
        сам.assertEqual(снимок['наблюдение'], '2026-10-08T12:00:00Z')
        итог = сам.построить()
        сам.assertEqual(итог['границы']['runtime'], 'unknown')
        сам.assertEqual(итог['границы']['текущие_наблюдения'], 'не запрашивались')
        сам.assertIsNone(json.loads(итог['кандидат'])['предпросмотр']['исполнители'][0]['снимок'])
        сам.ф.вход['снимок'] = снимок
        with сам.assertRaises(ValueError): сам.построить()

    def test_повторный_ключ_в_закреплённом_решении(сам):
        данные = байты(сам.ф.решение).replace(b'{', b'{"unknown":1,"unknown":2,', 1)
        источник = сам.ф.с.сохранить('повтор.json', данные)
        сам.ф.вход['переходы'][0]['источник'] = источник
        сам.ф.вход['выбранное'] = источник
        with сам.assertRaisesRegex(ValueError, 'повторное JSON'): сам.построить()

    def test_ручная_композиция_профиля_имеет_тот_же_смысл(сам):
        профиль = importlib.import_module('профиль_переходов_задачи_узла')
        сам.ф.состав()
        ручной = профиль.ручная_композиция(сам.ф.вход, корень=сам.ф.с.репо)
        итог = сам.построить()
        сам.assertEqual(ручной['кандидат'], итог['кандидат'])
        сам.assertEqual(ручной['предпросмотр'], итог['предпросмотр'])

    def test_возврат_к_закрытому_акт_через_новый_акт_запрещён(сам):
        прежний_акт = copy.deepcopy(сам.ф.решение['поручение'])
        сам.ф.переход(состояние='закрыт')
        сам.ф.переход(поручение=сам.ф.с.акт(ДОЧЬ), этап='второй-v2', состояние='открыт')
        сам.ф.переход(поручение=прежний_акт, этап='первый-v1', состояние='открыт')
        with сам.assertRaisesRegex(ValueError, 'покинутому ACT'): сам.построить()

    def test_возврат_к_готовому_акт_не_сбрасывает_результат(сам):
        прежний_акт = copy.deepcopy(сам.ф.решение['поручение'])
        готовое = сам.ф.с.сохранить('результат.md', b'ready\n')
        сам.ф.переход(результат={'состояние': 'готов', 'источник': готовое})
        сам.ф.переход(поручение=сам.ф.с.акт(ДОЧЬ), этап='второй-v2', результат=None)
        сам.ф.переход(поручение=прежний_акт, этап='первый-v1', результат=None)
        with сам.assertRaisesRegex(ValueError, 'покинутому ACT'): сам.построить()

    def test_неизвестный_исход_репозитория_не_сбрасывается(сам):
        сам.ф.переход(эффекты={'отправка': 'не было', 'репозиторий': 'unknown'})
        сам.assertEqual(сам.построить()['предпросмотр']['действие']['вид'], 'адресная сверка')
        сам.ф.переход(эффекты={'отправка': 'не было', 'репозиторий': 'подтверждён'})
        with сам.assertRaisesRegex(ValueError, 'unknown'): сам.построить()

    def test_новый_акт_не_переиспользует_покинутый_этап(сам):
        сам.ф.переход(состояние='закрыт')
        сам.ф.переход(поручение=сам.ф.с.акт(ДОЧЬ), этап='второй-v2', состояние='открыт')
        сам.ф.переход(поручение=сам.ф.с.акт(ДОЧЬ), этап='первый-v1', состояние='открыт')
        with сам.assertRaisesRegex(ValueError, 'покинутый этап'): сам.построить()

    def test_сырьё_неуспешного_работника_сохраняется(сам):
        профиль = importlib.import_module('профиль_переходов_задачи_узла')
        итог = профиль.запустить_работник([sys.executable, '-B', '-c',
            'import sys; sys.stdout.buffer.write(b"raw-out"); sys.stderr.buffer.write(b"raw-err"); sys.exit(7)'])
        сам.assertEqual(итог['код'], 7); сам.assertFalse(итог['тайм_аут'])
        сам.assertEqual(base64.b64decode(итог['stdout_base64']), b'raw-out')
        сам.assertEqual(base64.b64decode(итог['stderr_base64']), b'raw-err')
        выход = сам.ф.с.папка/'неуспешный-профиль.json'
        сырьё = профиль.сохранить_сырьё(выход, 1, итог)
        данные = (выход.parent/сырьё['имя']).read_bytes()
        сам.assertEqual(сырьё['sha256'], хэш(данные))
        сам.assertEqual(json.loads(данные), итог)

    def test_сырьё_тайм_аута_сохраняется_без_повтора(сам):
        профиль = importlib.import_module('профиль_переходов_задачи_узла')
        итог = профиль.запустить_работник([sys.executable, '-B', '-c',
            'import sys,time; sys.stdout.buffer.write(b"partial-out"); sys.stdout.buffer.flush(); time.sleep(10)'],
            тайм_аут=0.2)
        сам.assertIsNone(итог['код']); сам.assertTrue(итог['тайм_аут'])
        сам.assertEqual(base64.b64decode(итог['stdout_base64']), b'partial-out')
        выход = сам.ф.с.папка/'тайм-аут-профиля.json'
        сырьё = профиль.сохранить_сырьё(выход, 1, итог)
        сам.assertEqual(json.loads((выход.parent/сырьё['имя']).read_bytes()), итог)



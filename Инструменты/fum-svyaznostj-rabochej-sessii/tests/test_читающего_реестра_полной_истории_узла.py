        дескрипторы = []
        настоящее = читатель.os.open
        def открыть(путь, *аргументы, **параметры):
            дескриптор = настоящее(путь, *аргументы, **параметры)
            if str(путь) in пути:
                дескрипторы.append(дескриптор)
            return дескриптор
        with patch.object(читатель.os, 'open', открыть), patch.object(
                читатель, '_рождение', side_effect=KeyboardInterrupt):
            with сам.assertRaises(KeyboardInterrupt):
                читатель.прочитать(корень, вход, выбор)
        сам.assertTrue(дескрипторы)
        for дескриптор in дескрипторы:
            with сам.assertRaises(OSError):
                os.fstat(дескриптор)
        сам.assertEqual(до, {п: Path(п).read_bytes() for п in пути})


def гит(корень, *аргументы):
    среда = {ключ: значение for ключ, значение in os.environ.items()
        if not ключ.startswith('GIT_')}
    среда['GIT_OPTIONAL_LOCKS'] = '0'
    return subprocess.check_output(['git', '-C', str(корень),
        '-c', 'core.hooksPath=' + str(корень / 'отключённые-хуки'), *аргументы], env=среда,
        stderr=subprocess.PIPE).decode().strip()



def создать_фикстуру(корень, строки=None, *, бюджет=None, граница=None, строки_владельца=None):
    корень = Path(корень).resolve()
    гит(корень, 'init', '-q')
    гит(корень, 'config', 'user.name', 'Открытая фикстура')
    гит(корень, 'config', 'user.email', 'fixture@example.invalid')
    (корень / 'основание.txt').write_text('Конечная открытая фикстура.\n')
    гит(корень, 'add', 'основание.txt')
    гит(корень, 'commit', '-qm', 'Основание лаборатории')
    коммит = гит(корень, 'rev-parse', 'HEAD')
    контроль = {'ветка': 'refs/heads/codex/контроль-фикстуры', 'коммит': коммит}
    гит(корень, 'update-ref', контроль['ветка'], коммит)
    источники = []
    рождения = {}
    for роль, задача in [('координатор', КООРДИНАТОР), ('владелец', ВЛАДЕЛЕЦ)]:
        р = старый.байты(рождение(корень, коммит, задача))
        выбранные = ([нейтральная(1, задача)] if строки_владельца is None else строки_владельца
            ) if роль == 'владелец' else ([нейтральная(1, задача)] if строки is None else строки)
        данные = bytearray(р)
        начальная = {'граница': len(р), 'sha256': hashlib.sha256(р).hexdigest()}
        for запись in выбранные:
            данные.extend(старый.байты(запись))
            if граница == запись['ordinal'] and роль == 'координатор':
                начальная = {'граница': len(данные), 'sha256': hashlib.sha256(данные).hexdigest()}
        путь = корень / (роль + '.jsonl')
        путь.write_bytes(данные)
        путь.chmod(0o600)
        источники.append({'роль': роль, 'задача': задача, 'путь': str(путь),
            'начало': начальная, 'конец': {'граница': len(данные),
                'sha256': hashlib.sha256(данные).hexdigest()}, 'промежуточные': []})
        рождения[роль] = {'задача': задача, 'хэш_корня': старый.хэш(str(корень).encode()),
            'коммит': коммит}
    ресурс = {'схема': 'fum.ресурсы-читающего-реестра-полной-истории-узла.1',
        'координатор': КООРДИНАТОР, 'владелец': ВЛАДЕЛЕЦ, 'контроль': контроль,
        'рождения': рождения, 'пределы': бюджет or пределы()}
    данные_ресурса = старый.байты(ресурс)
    (корень / 'ресурс.json').write_bytes(данные_ресурса)
    гит(корень, 'add', 'ресурс.json')
    гит(корень, 'commit', '-qm', 'Независимый выбор конечных ресурсов КООРДИНАТОР')
    выбор = {'коммит': гит(корень, 'rev-parse', 'HEAD'), 'путь': 'ресурс.json',
        'sha256': hashlib.sha256(данные_ресурса).hexdigest()}
    вход = {'схема': 'fum.вход-читающего-реестра-полной-истории-узла.1',
        'координатор': КООРДИНАТОР, 'владелец': ВЛАДЕЛЕЦ, 'контроль': контроль,
        'корни': {'координатор': str(корень), 'владелец': str(корень)},
        'источники': источники}
    return вход, выбор, ресурс


def перевыбрать_ресурс(корень, ресурс):
    данные = старый.байты(ресурс)
    (корень / 'ресурс.json').write_bytes(данные)
    гит(корень, 'add', 'ресурс.json')
    гит(корень, 'commit', '-qm', 'Следующий независимый лабораторный выбор')
    return {'коммит': гит(корень, 'rev-parse', 'HEAD'), 'путь': 'ресурс.json',
        'sha256': старый.хэш(данные)}



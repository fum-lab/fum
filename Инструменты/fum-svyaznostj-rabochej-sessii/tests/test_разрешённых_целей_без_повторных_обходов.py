"""Конечные цели: линейное перечисление, свежесть, порядок и прежние отказы."""
import os
from pathlib import Path
import re
import subprocess
import tempfile
import unittest
from unittest import mock

import профиль_разрешённых_целей as профиль

коммит = профиль.коммит


class РазрешённыеЦели(unittest.TestCase):
    def test_общий_каталог_читается_один_раз_на_независимый_вызов(сам):
        with профиль.стенд(32) as (корень, каталог, цели):
            до = профиль.снимок(корень)
            for _ in range(2):
                наблюдение = профиль.измерить(корень, каталог, цели)
                сам.assertEqual(наблюдение['перечислений'], 1)
                сам.assertEqual(наблюдение['имён'], len(цели))
            сам.assertEqual(профиль.снимок(корень), до)

    def test_неверный_список_отказывает_до_обхода(сам):
        with профиль.стенд(1) as (корень, _, цели):
            for значение in (None, [], (), ['x', 'x'], [1], 'x'):
                with сам.subTest(значение=значение), mock.patch.object(
                        коммит.охват, 'точный_путь') as путь:
                    with сам.assertRaisesRegex(коммит.ОшибкаКоммита,
                            'нужен явный конечный список разрешённых целей без повторов'):
                        коммит.разрешённые_цели(корень, {'разрешённые_цели': значение})
                    путь.assert_not_called()

    def test_точные_отказы_и_остановка_на_первом(сам):
        with профиль.стенд(1) as (корень, _, цели):
            (корень / 'ссылка').symlink_to(корень / цели[0])
            абсолютная_цель = str(корень / 'абсолютная-цель.txt')
            случаи = (
                ('../x', ValueError, "Требуется точная относительная цель: '../x'"),
                (абсолютная_цель, ValueError,
                    f'Требуется точная относительная цель: {абсолютная_цель!r}'),
                ('.git/x', ValueError, "Требуется точная относительная цель: '.git/x'"),
                ('цели//x', ValueError, "Требуется точная относительная цель: 'цели//x'"),
                ('ссылка', ValueError, 'Символическая ссылка в цели: ссылка'),
                ('ЦЕЛИ/0000.txt', ValueError, 'Неверный регистр цели: ЦЕЛИ/0000.txt'),
                ('цели', коммит.ОшибкаКоммита, 'разрешение каталога вместо конечного состава'),
            )
            for имя, тип, текст in случаи:
                with сам.subTest(имя=имя), mock.patch.object(коммит.охват,
                        'точный_путь', wraps=коммит.охват.точный_путь) as путь:
                    with сам.assertRaisesRegex(тип, '^' + re.escape(текст) + '$'):
                        коммит.разрешённые_цели(корень, {'разрешённые_цели': [имя, цели[0]]})
                    сам.assertEqual([в.args[1] for в in путь.call_args_list], [имя])

    def test_отсутствующая_будущая_цель_сохраняет_порядок_и_исходный_список(сам):
        with профиль.стенд(1) as (корень, _, существующие):
            цели = ['будущий/файл.txt', *существующие]
            with mock.patch.object(коммит.охват, 'точный_путь',
                    wraps=коммит.охват.точный_путь) as путь:
                сам.assertIs(коммит.разрешённые_цели(корень,
                    {'разрешённые_цели': цели}), цели)
            сам.assertEqual([в.args[1] for в in путь.call_args_list], цели)
            сам.assertFalse((корень / 'будущий').exists())

    def test_смена_регистра_между_целями_видна_при_восстановленном_mtime(сам):
        with профиль.стенд(2) as (корень, каталог, цели):
            исходное = коммит.охват.точный_путь
            вызовы = []

            def проверить(*а):
                результат = исходное(*а)
                вызовы.append(а[1])
                if len(вызовы) == 1:
                    до = каталог.stat()
                    (корень / цели[1]).rename(каталог / '0001.TXT')
                    os.utime(каталог, ns=(до.st_atime_ns, до.st_mtime_ns))
                return результат

            with mock.patch.object(коммит.охват, 'точный_путь', проверить):
                with сам.assertRaisesRegex(ValueError,
                        '^Неверный регистр цели: цели/0001.txt$'):
                    коммит.разрешённые_цели(корень, {'разрешённые_цели': цели})
            сам.assertEqual(вызовы, [цели[0]])

    def test_исходное_исключение_не_меняется_и_не_повторяется(сам):
        with профиль.стенд(2) as (корень, _, цели):
            ошибка = OSError('Исходный отказ пути')
            with mock.patch.object(коммит.охват, 'точный_путь',
                    side_effect=ошибка) as путь:
                with сам.assertRaises(OSError) as исход:
                    коммит.разрешённые_цели(корень, {'разрешённые_цели': цели})
            сам.assertIs(исход.exception, ошибка)
            сам.assertEqual(путь.call_count, 1)


class ГраницаПрофиля(unittest.TestCase):
    def test_выход_в_обычном_и_bare_Git_не_достигает_стенда(сам):
        with tempfile.TemporaryDirectory() as временный:
            основа = Path(временный).resolve()
            for bare in (False, True):
                корень = основа / ('bare.git' if bare else 'worktree')
                subprocess.run(['git', 'init', *(['--bare'] if bare else []), str(корень)],
                    check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                выход = корень / 'измерение.json'
                with mock.patch.object(профиль.sys, 'argv', ['профиль', '--выход', str(выход)]), \
                        mock.patch.object(профиль, 'стенд',
                            side_effect=AssertionError('Стенд начал подготовку')) as стенд:
                    with сам.assertRaisesRegex(ValueError, 'вне Git'):
                        профиль.главная()
                стенд.assert_not_called()
                сам.assertFalse(выход.exists())


if __name__ == '__main__':
    unittest.main()

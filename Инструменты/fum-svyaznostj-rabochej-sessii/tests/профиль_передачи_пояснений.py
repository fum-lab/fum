"""Парные серии реального CLI: все JSON-пакеты, определение и явный получатель."""
import argparse
import hashlib
import json
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from компактный_остаток import закодировать, требовать
from пояснения_ответа import подтвердить, подготовить_подтверждение, восстановить

КОРЕНЬ = Path(__file__).resolve().parents[3]
ЗАДАЧА = "00000000-0000-0000-0000-000000000165"


def итог_серии(шаги):
    return {"запросы_байты": sum(шаг["запрос_байты"] for шаг in шаги),
        "ответы_байты": sum(шаг["ответ_байты"] for шаг in шаги),
        "всего_байтов": sum(шаг["запрос_байты"] + шаг["ответ_байты"] for шаг in шаги),
        "определения_внутри_ответов_байты": sum(шаг["определение_байты"] for шаг in шаги),
        "подтверждения_внутри_запросов_байты": sum(шаг["подтверждение_байты"] for шаг in шаги),
        "полных_форм": sum(шаг["форма"] == "полная" for шаг in шаги),
        "ссылочных_форм": sum(шаг["форма"] == "ссылочная" for шаг in шаги),
        "длительность_нс": sum(шаг["длительность_нс"] for шаг in шаги)}


def серия(путь, хэш, сценарий, число, новая):
    шаги = []
    определение = None
    подтверждение = None
    предыдущий = None
    передача = "00000000-0000-0000-0000-000000000001"
    эталон = None
    for номер in range(число):
        начало = time.perf_counter_ns()
        if новая and сценарий == "с_утратой" and номер == 4:
            определение = None  # Старый ACK намеренно остаётся: одного его недостаточно.
            передача = "00000000-0000-0000-0000-000000000002"
        явное_подтверждение = новая and (номер == 2 or (сценарий == "с_утратой" and номер == 6))
        if явное_подтверждение:
            подтверждение = подтвердить(предыдущий, передача)
        готовое = подготовить_подтверждение(определение, подтверждение, передача) if новая else None
        параметры = {"снимок": str(путь), "sha256": хэш, "задача": ЗАДАЧА,
            "максимум_байтов": 16000, "путь_в_результате": True, "профиль": "прежний"}
        команда = [sys.executable, "-B", str(КОРЕНЬ / "Инструменты/fum-svyaznostj-rabochej-sessii/scripts/показать-ответ-задачи.py"),
            "--снимок", str(путь), "--sha256", хэш, "--задача", ЗАДАЧА, "--путь-в-результате", "--максимум-байтов", "16000"]
        if новая:
            параметры.update(версия_передачи="пояснения-1", передача_пояснений=передача, подтверждение_пояснений=готовое)
            команда += ["--версия-передачи", "пояснения-1", "--передача-пояснений", передача,
                "--подтверждение-пояснений", закодировать(готовое).decode().rstrip("\n")]
        запрос = закодировать(параметры)
        перед_процессом = time.perf_counter_ns()
        процесс = subprocess.run(команда, capture_output=True, check=True)
        после_процесса = time.perf_counter_ns()
        выдача = json.loads(процесс.stdout)
        if новая:
            полный = восстановить(выдача, определение, передача)
            if выдача["форма"] == "полная":
                определение = выдача["определение"]
            предыдущий = выдача
        else:
            полный = выдача
        конец = time.perf_counter_ns()
        # Проверка семантики и сбор отчёта находятся за измеряемой границей.
        полные_байты = закодировать(полный)
        if эталон is None:
            эталон = полные_байты
        требовать(эталон == полные_байты, "Изменился восстановленный ответ серии")
        требовать(полный["живой_источник_перепроверен"] is False and полный["завершение_задачи_доказано"] is False,
            "Потеряны признаки границ доказательства")
        шаги.append({"номер": номер + 1, "запрос_байты": len(запрос), "ответ_байты": len(процесс.stdout),
            "подтверждение_байты": len(закодировать(готовое)) - 1 if готовое is not None else 0,
            "определение_байты": len(закодировать(выдача["определение"])) - 1 if новая and выдача["определение"] is not None else 0,
            "форма": выдача["форма"] if новая else "полная", "явное_подтверждение": явное_подтверждение,
            "длительность_нс": конец - начало, "команда_нс": после_процесса - перед_процессом,
            "получатель_нс": конец - после_процесса,
            "восстановленные_байты": len(полные_байты), "хэш_восстановленного": hashlib.sha256(полные_байты).hexdigest()})
    return {"версия": "пояснения-1" if новая else "прежняя", "шаги": шаги, "итог": итог_серии(шаги)}


def измерить(повторы=7):
    требовать(type(повторы) is int and 1 <= повторы <= 20, "Неверное число повторов")
    фикстура = Path(__file__).with_name("фикстуры") / "малый-ответ-MCP.json"
    данные = фикстура.read_bytes()
    хэш = hashlib.sha256(данные).hexdigest()
    серии = []
    with tempfile.TemporaryDirectory(prefix="fum-explanations-") as каталог:
        путь = Path(каталог) / "снимок-ёж.json"
        путь.write_bytes(данные)
        for повтор in range(повторы):
            for сценарий, число in (("короткий", 6), ("повторный", 24), ("с_утратой", 8)):
                пара = {}
                for новая in ((False, True) if повтор % 2 == 0 else (True, False)):
                    вариант = серия(путь, хэш, сценарий, число, новая)
                    пара[вариант["версия"]] = вариант
                требовать([шаг["хэш_восстановленного"] for шаг in пара["прежняя"]["шаги"]]
                    == [шаг["хэш_восстановленного"] for шаг in пара["пояснения-1"]["шаги"]], "Пара изменила результат")
                серии.append({"повтор": повтор + 1, "сценарий": сценарий, "варианты": пара})
        требовать(путь.read_bytes() == данные, "Снимок изменился")
    сравнение = {}
    for сценарий in ("короткий", "повторный", "с_утратой"):
        выборка = [пара for пара in серии if пара["сценарий"] == сценарий]
        итоги = {версия: {"байты": выборка[0]["варианты"][версия]["итог"]["всего_байтов"],
            "медиана_нс": statistics.median(пара["варианты"][версия]["итог"]["длительность_нс"] for пара in выборка)}
            for версия in ("прежняя", "пояснения-1")}
        до, после = итоги["прежняя"], итоги["пояснения-1"]
        предел = до["медиана_нс"] + max(50000000, до["медиана_нс"] * .25)
        сравнение[сценарий] = {"варианты": итоги, "экономия_байтов": до["байты"] - после["байты"],
            "предел_времени_нс": предел, "временной_критерий_пройден": после["медиана_нс"] <= предел}
    исходники = ["scripts/показать-ответ-задачи.py", "scripts/пояснения_ответа.py", "scripts/компактный_ответ_задачи.py",
        "scripts/компактный_остаток.py", "профили/пояснения-ответа-1.json", "tests/профиль_передачи_пояснений.py",
        "tests/фикстуры/малый-ответ-MCP.json"]
    каталог_инструмента = Path(__file__).resolve().parents[1]
    return {"схема": "fum.профиль-передачи-пояснений.1", "версия_питона": sys.version.split()[0],
        "исходники": {имя: hashlib.sha256((каталог_инструмента / имя).read_bytes()).hexdigest() for имя in исходники},
        "вход": {"sha256": хэш, "байты": len(данные)}, "повторы": повторы,
        "граница": "Все пакеты параметров и ответы JSON с UTF-8/LF и путём; определения/ACK внутри них не суммируются второй раз. CLI/диск реальные. Потребитель и его явное подтверждение синтетические; API, сеть, токены и RSS не измеряются. argv локального процесса не является дополнительным JSON-пакетом. Проверка семантики вне таймера; подготовка запроса, CLI, разбор и восстановление внутри. Время setup не измеряется; файл записан один раз, API-вызовов ноль.",
        "сравнение": сравнение, "серии": серии}


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    разбор.add_argument("--повторы", type=int, default=7)
    параметры = разбор.parse_args()
    результат = измерить(параметры.повторы)
    параметры.выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n", encoding="utf8")
    print(json.dumps(результат["сравнение"], ensure_ascii=False))

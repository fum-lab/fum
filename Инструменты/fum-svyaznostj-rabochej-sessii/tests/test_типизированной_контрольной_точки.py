    def test_повреждённая_готовая_квитанция_отказывает_без_записи(сам):
        ф, вход, первый = сам.новая()
        файл = Path(ф.параметры['квитанция']); исходная = файл.read_bytes()
        случаи = [('результат', None), ('коммит', None), ('коммит', '0' * 40),
                  ('коммит', первый['коммит'][:7]), ('автор', первый['автор'] + ' подмена'),
                  ('коммиттер', первый['коммиттер'] + ' подмена'),
                  ('дерево', '0' * 40), ('родители', []), ('сообщение_sha256', '0' * 64),
                  ('лишнее_поле', True), ('процесс', None), ('код', 1), ('код', False),
                  ('тайм_аут', True), ('исполнение_завершено', False), ('прерывание', 'SIGINT'),
                  ('наблюдённый_коммит', None), ('наблюдённый_коммит', '0' * 40),
                  ('ожидание', None), ('ожидание.исходный_коммит', None),
                  ('ожидание.исходный_коммит', '0' * 40), ('ожидание.родители', []),
                  ('ожидание.сообщение_sha256', '0' * 64), ('ожидание.явные_даты', None),
                  ('ожидание.явные_даты', {'GIT_AUTHOR_DATE': 'вчера'}),
                  ('ожидание.автор', ['имя', 'email']), ('ожидание.коммиттер', ['имя', 'email']),
                  ('ожидание.лишнее_поле', True),
                  ('дублирование', True),
                  ('состояние', 'намерение'), ('схема', 'fum.квитанция-создания-коммита.99')]
        for поле, значение in случаи:
            with сам.subTest(поле=поле, значение=значение):
                квитанция = json.loads(исходная)
                if поле in ('результат', 'процесс'):
                    квитанция.pop(поле)
                elif поле in ('состояние', 'схема'):
                    квитанция[поле] = значение
                elif поле == 'наблюдённый_коммит':
                    if значение is None: квитанция.pop(поле)
                    else: квитанция[поле] = значение
                elif поле == 'ожидание':
                    квитанция.pop(поле)
                elif поле.startswith('ожидание.'):
                    квитанция['ожидание'][поле.split('.', 1)[1]] = значение
                elif поле == 'дублирование':
                    pass
                elif поле in ('код', 'тайм_аут', 'исполнение_завершено', 'прерывание'):
                    квитанция['процесс'][поле] = значение
                elif поле == 'коммит' and значение is None:
                    квитанция['результат'].pop(поле)
                else:
                    квитанция['результат'][поле] = значение
                текст = json.dumps(квитанция, ensure_ascii=False, indent=3) + '\n'
                if поле == 'дублирование': текст = '{"состояние":"проверен",' + текст[1:]
                файл.write_text(текст)
                до = сам.снимок(ф)
                def отказ():
                    with сам.assertRaises(база.коммит.ОшибкаКоммита):
                        вход.создать()
                сам.без_нового_эффекта(отказ)
                сам.assertEqual(до, сам.снимок(ф))


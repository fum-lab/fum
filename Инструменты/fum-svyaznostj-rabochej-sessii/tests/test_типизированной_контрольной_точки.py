class РаннийОтказ(unittest.TestCase):
    def setUp(сам):
        сам.пример = база.СозданиеКоммита()
        сам.пример.setUp()
        сам.addCleanup(сам.пример.doCleanups)
        сам.пример.готовить(объявить_готовность=False)
        сам.к = база.коммит
        сам.подготовка = Path(сам.пример.параметры['подготовка'])

    def test_неверный_идентификатор_отказывает_до_чтения_команд(сам):
        путь_записи = str(сам.пример.запрос.parent / 'материалы/запуски-проверок' /
                       ('1_' + база.ЗАПУСК + '.json'))
        случаи = [[], [база.ЗАПУСК, база.ЗАПУСК], [путь_записи],
                  ['00000000-0000-0000-0000-00000000000A'], [13]]
        for номера in случаи:
            with сам.subTest(номера=номера):
                with mock.patch.object(сам.к, 'команды', wraps=сам.к.команды) as читатель:
                    with сам.assertRaises(сам.к.ОшибкаКоммита):
                        сам.к.объявить_готовность(сам.подготовка, номера, 600)
                    сам.assertEqual(0, читатель.call_count,
                        'Некорректный перечень UUID прочитал первичный native JSONL')

    def отказ_до_источников(сам, действие):
        голова = сам.пример.гит('rev-parse', 'HEAD')
        индекс = (сам.пример.корень / '.git/index').read_bytes()
        with mock.patch.object(сам.к, 'команды', wraps=сам.к.команды) as команды, \
             mock.patch.object(сам.к, 'наблюдать_модель', wraps=сам.к.наблюдать_модель) as модель:
            with сам.assertRaises(сам.к.ОшибкаКоммита):
                действие()
            сам.assertEqual((0, 0), (команды.call_count, модель.call_count))
        сам.assertEqual(голова, сам.пример.гит('rev-parse', 'HEAD'))
        сам.assertEqual(индекс, (сам.пример.корень / '.git/index').read_bytes())

    def готово(сам):
        return сам.к.объявить_готовность(сам.подготовка, [база.ЗАПУСК], 600)

    def test_чужие_голова_ветка_родители_и_точные_пути(сам):
        оригинал = сам.подготовка.read_bytes()
        случаи = [('исходный_коммит', '0' * 40), ('ветка', 'refs/heads/codex/чужая'),
                  ('родители', [сам.пример.начало, '0' * 40]),
                  ('корень', str(сам.пример.корень) + '/.'),
                  ('запрос', база.ЗАПРОС.replace('Журнал/', 'Журнал/../Журнал/')),
                  ('запрос', база.ЗАПРОС.replace('Журнал/', 'журнал/'))]
        for поле, значение in случаи:
            with сам.subTest(поле=поле):
                данные = json.loads(оригинал); данные['параметры'][поле] = значение
                сам.подготовка.write_bytes(сам.к.байты(данные))
                сам.отказ_до_источников(сам.готово)
        сам.подготовка.write_bytes(оригинал)
        ссылка = сам.пример.каталог / 'ссылка.json'; ссылка.symlink_to(сам.подготовка)
        сам.отказ_до_источников(lambda: сам.к.объявить_готовность(ссылка, [база.ЗАПУСК], 600))

    def test_изменённые_байты_режим_и_индексные_флаги(сам):
        данные = сам.пример.корень / 'данные.txt'; исходные = данные.read_bytes()
        данные.write_text('после проверки\n')
        сам.отказ_до_источников(сам.готово); данные.write_bytes(исходные)
        данные.chmod(0o755)
        сам.отказ_до_источников(сам.готово); данные.chmod(0o644)
        for флаг in ('skip-worktree', 'assume-unchanged'):
            with сам.subTest(флаг=флаг):
                сам.пример.гит('update-index', '--' + флаг, 'данные.txt')
                сам.отказ_до_источников(сам.готово)
                сам.пример.гит('update-index', '--no-' + флаг, 'данные.txt')

    def test_конфликтные_стадии_индекса_до_источника(сам):
        ф = сам.пример; объект = ф.гит('rev-parse', 'HEAD:данные.txt').strip()
        данные = ('0 ' + '0' * 40 + '\tданные.txt\n' +
                  '100644 ' + объект + ' 1\tданные.txt\n100644 ' + объект + ' 2\tданные.txt\n').encode()
        subprocess.run(['git', '-C', str(ф.корень), 'update-index', '--index-info'], input=данные, check=True)
        сам.отказ_до_источников(сам.готово)

    def test_подмена_между_двумя_чтениями_подготовки(сам):
        оригинал = сам.к.прочитать_подготовку_готовности
        def прочитать(*аргументы, **параметры):
            подготовка, вход = оригинал(*аргументы, **параметры)
            подготовка['сообщение_sha256'] = '0' * 64
            return подготовка, вход
        with mock.patch.object(сам.к, 'прочитать_подготовку_готовности', side_effect=прочитать):
            сам.отказ_до_источников(сам.готово)

    def test_устаревший_отпечаток_и_чужой_идентификатор(сам):
        сам.отказ_до_источников(lambda: сам.к.объявить_готовность(сам.подготовка,
            ['00000000-0000-0000-0000-000000000099'], 600))
        данные = сам.пример.корень / 'данные.txt'; данные.write_text('новый индекс\n')
        сам.пример.гит('add', 'данные.txt')
        сам.отказ_до_источников(сам.готово)

    def test_повтор_готовности_сохраняет_эпоху_и_предел(сам):
        первый = сам.готово(); файл = Path(первый['путь']); состояние = сам.к.готовность.прочитать(файл)
        второй = сам.готово()
        сам.assertEqual(первый['готов_в_наносекундах_эпохи'], второй['готов_в_наносекундах_эпохи'])
        сам.отказ_до_источников(lambda: сам.к.объявить_готовность(сам.подготовка, [база.ЗАПУСК], 601))
        сам.assertEqual(состояние['готов_в_наносекундах_эпохи'], сам.к.готовность.прочитать(файл)['готов_в_наносекундах_эпохи'])
        # Порог задержки разрешает фиксацию; он не является временем истечения.
        поздно = состояние['готов_в_наносекундах_эпохи'] + 601_000_000_000
        _, решение = сам.к.готовность.поколения.оценить(состояние, состояние['поколения'][-1]['снимок'], поздно)
        сам.assertTrue(решение['фиксировать_этап'])
        сам.assertEqual('зафиксировать-этап', решение['действие'])



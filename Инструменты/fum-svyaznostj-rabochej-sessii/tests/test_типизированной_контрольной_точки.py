        ф.гит('checkout', '-q', 'codex/фикстура'); ф.гит('merge', '--no-ff', '--no-commit', второй)
        ф.параметры['родители'].append(второй); ф.параметры['разрешённые_цели'].append('вклад.txt')
        ф.запрос.write_text(ф.запрос.read_text() + '- [Вклад](../../вклад.txt).\n'); ф.готовить(False)
        вход = фасад.ВходКонтрольнойТочки.из_значений(ф.параметры['подготовка'], [база.ЗАПУСК])
        вход.готово(600); итог = вход.создать(); сам.assertEqual([ф.начало, второй], итог['родители'])


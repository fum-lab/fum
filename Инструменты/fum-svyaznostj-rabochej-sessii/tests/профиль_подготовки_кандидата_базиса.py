#!/usr/bin/env python3
"""Свежие потребители одного K/R/T, включая парный полный путь точного C5/C6."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sys
import time
from types import SimpleNamespace

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_подготовки_кандидата_базиса import ПримерПодготовки, СУБЪЕКТ, гит, полный_снимок


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--каталог-raw', dest='каталог', type=Path, required=True)
    разбор.add_argument('--выход', type=Path, required=True)
    разбор.add_argument('--история', type=Path, help='Приватная первая фикстура прежнего измерения для того же K/R/T')
    разбор.add_argument('--версия', type=int, choices=(1, 2), default=1)
    разбор.add_argument('--общая-база', action='store_true', help='Настоящие linked B/REPORT/planner одной новой базы')
    разбор.add_argument('--парный-C5', action='store_true', help='Три пары точного Git C5 и текущего кода; нагрузка 32 поддерева')
    параметры = разбор.parse_args()
    if параметры.общая_база and параметры.версия != 2:
        raise ValueError('Общий успешный профиль требует новую версию 2; legacy отказ проверяется отдельно')
    if параметры.парный_C5 and (not параметры.общая_база or параметры.история):
        raise ValueError('Парный профиль требует новую общую изолированную историю версии 2')
    база = параметры.каталог
    if not база.is_absolute() or база.resolve() != база or база.exists():
        raise ValueError('Нужен новый абсолютный физический каталог')
    if any(os.path.lexists(п / '.git') for п in (база, *база.parents)):
        raise ValueError('Профиль хранит частные входы вне Git')
    база.mkdir(mode=0o700)
    до = None
    порядок = ['до', 'после', 'после', 'до', 'до', 'после'] if параметры.парный_C5 else ['после'] * 3
    if параметры.парный_C5:
        до = база / 'код-до.py'
        данные_до = гит(СУБЪЕКТ.parents[3], 'show', '10812072c86d66521308ad3f60278105422e11df:'
            'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/подготовка_кандидата_базиса.py')
        assert hashlib.sha256(данные_до).hexdigest() == '8b36046ee0a40be777e1af7dfa488b4cfee245c8703464a68205d47e501e9d52'
        до.write_bytes(данные_до); до.chmod(0o400)
    def субъект(номер):
        return до if порядок[номер - 1] == 'до' else СУБЪЕКТ
    начала = time.perf_counter_ns()
    первый = база / '1'; первый.mkdir(mode=0o700)
    история = None
    ожидаемый_предмет = None
    if параметры.история:
        исходный = json.loads((параметры.история / 'вход-cli.json').read_bytes())
        выбор = исходный['выбор_базиса']
        вход_построителя = json.loads(Path(выбор['вход_построителя']['путь']).read_bytes())
        акт = json.loads(гит(Path(выбор['отчётный_корень']), 'show', выбор['назначение']['коммит'] + ':' + выбор['назначение']['путь']))
        происхождение = json.loads(гит(Path(выбор['отчётный_корень']), 'show', акт['построитель']['коммит'] + ':' + акт['построитель']['путь']))
        история = SimpleNamespace(корень=Path(вход_построителя['корень']), объекты=Path(вход_построителя['каталог_объектов']),
            вход=вход_построителя, выбор=происхождение['выбор_решений'],
            ф=SimpleNamespace(идентичность=вход_построителя['первый_цикл']['идентичность']))
        ожидаемый_предмет = json.loads((параметры.история / 'план-cli.json').read_bytes())['предмет']
    ф = ПримерПодготовки(первый, история=история, связанный=параметры.общая_база,
        общий=параметры.общая_база, версия=параметры.версия, субъект=субъект(1),
        нагрузка=32 if параметры.парный_C5 else 0)
    подготовка_истории = time.perf_counter_ns() - начала
    исходники = {СУБЪЕКТ.name: hashlib.sha256(СУБЪЕКТ.read_bytes()).hexdigest(),
        Path(__file__).name: hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'test_подготовки_кандидата_базиса.py': hashlib.sha256(Path(__file__).with_name('test_подготовки_кандидата_базиса.py').read_bytes()).hexdigest()}
    результаты = []
    for номер in range(1, len(порядок) + 1):
        начало_цикла = time.time_ns()
        монотонное_начало_цикла = time.perf_counter_ns()
        начало_подготовки = time.perf_counter_ns()
        if номер != 1:
            каталог = база / str(номер); каталог.mkdir(mode=0o700)
            ф = ПримерПодготовки(каталог, история=ф.п, связанный=параметры.общая_база,
                общий=параметры.общая_база, версия=параметры.версия, субъект=субъект(номер))
        служебные = []
        сценарий = None
        if параметры.версия == 2 and параметры.общая_база:
            сценарий = ('абсолютный', 'маркер', 'смешанный')[(номер - 1) // 2 if параметры.парный_C5 else номер - 1]
            гит(ф.корень, 'config', '--local', 'extensions.worktreeConfig', 'true')
            for корень in (ф.корень, ф.отчёт):
                админ = Path(гит(корень, 'rev-parse', '--absolute-git-dir').decode().strip())
                данные = (b'[codex]\n\tlocalEnvironmentConfigPath = __none__\n'
                    if сценарий == 'маркер' or (сценарий == 'смешанный' and корень == ф.корень)
                    else f'[codex]\nlocalenvironmentconfigpath = {ф.каталог / "not-opened.toml"}\n'.encode())
                (админ / 'config.worktree').write_bytes(данные)
            общий = Path(гит(ф.корень, 'rev-parse', '--git-common-dir').decode().strip())
            общий = (общий if общий.is_absolute() else ф.корень / общий).resolve()
            if сценарий == 'смешанный':
                with (общий / 'config').open('ab') as поток:
                    поток.write(b'[codex]\n\tlocalEnvironmentConfigPath = __none__\n')
            чужой = Path(гит(ф.планировщик, 'rev-parse', '--absolute-git-dir').decode().strip())
            служебные = [общий / 'fum-branch-next-step/claims.lock',
                общий / 'fum-branch-task-gate/.transitions.lock', чужой / 'service/worker.lock']
            for файл in служебные:
                файл.parent.mkdir(parents=True, exist_ok=True); файл.write_bytes(b'permanent sentinel\n'); файл.chmod(0o600)
        конфиги = [Path(гит(к, 'rev-parse', '--absolute-git-dir').decode().strip()) / 'config.worktree'
            for к in (ф.корень, ф.отчёт)] if служебные else []
        if служебные: конфиги.append(общий / 'config')
        конфиги_до = [п.read_bytes() for п in конфиги]
        def снимок_служебных():
            return [{'sha256': hashlib.sha256(п.read_bytes()).hexdigest(), 'режим': п.stat().st_mode} for п in служебные]
        служебные_до = снимок_служебных()
        подготовка = time.perf_counter_ns() - начало_подготовки + (подготовка_истории if номер == 1 else 0)
        процессы = []
        def вызвать(действие, план=None, выбор=None):
            начало = time.perf_counter_ns()
            процесс = ф.потребитель(действие, план, выбор, журнал=False,
                тайм_аут=600 if параметры.парный_C5 else 120)
            длительность = time.perf_counter_ns() - начало
            имя = str(len(процессы) + 1) + '-' + действие
            (ф.каталог / (имя + '.stdout')).write_bytes(процесс.stdout)
            (ф.каталог / (имя + '.stderr')).write_bytes(процесс.stderr)
            if процесс.returncode:
                raise ValueError('Свежий consumer отказал: ' + процесс.stderr.decode())
            метрики = json.loads(процесс.stderr)
            пакет = метрики.get('пакетный_канал_деревьев')
            if пакет is not None:
                assert пакет['вызовов'] == пакет['процессов'] > 0
                assert пакет['запросов'] == пакет['ответов'] == 2 * пакет['объектов'] + пакет['отсутствующих']
                assert пакет['байтов_ввода'] == 96 * пакет['объектов'] + 46 * пакет['отсутствующих']
                assert пакет['байтов_неразобранных'] == 0 and пакет['отказов'] == 0
                assert пакет['байтов_вывода'] == sum(пакет[к] for к in
                    ('байтов_заголовков', 'байтов_содержимого', 'байтов_разделителей'))
                assert метрики['процессов'] >= пакет['процессов']
            процессы.append({'действие': действие, 'длительность_целого_процесса_наносекунды': длительность,
                'код': процесс.returncode, 'stdout_sha256': hashlib.sha256(процесс.stdout).hexdigest(),
                'stderr_sha256': hashlib.sha256(процесс.stderr).hexdigest(), **метрики})
            return json.loads(процесс.stdout)
        план = вызвать('план')
        if параметры.общая_база:
            assert план['отсутствующие_деревья'], 'Каждый повтор требует собственной исходной ODB без T'
        начало_выбора = time.perf_counter_ns()
        выбор = ф.выбрать(план)
        выбор_подготовка = time.perf_counter_ns() - начало_выбора
        вызвать('применить', план, выбор)
        вызвать('проверить', план, выбор)
        посторонний_коммит = None
        if параметры.версия == 2:
            начало_коммита = time.perf_counter_ns()
            гит(ф.планировщик, 'commit', '--allow-empty', '-qm', 'Посторонний коммит перед replay')
            посторонний_коммит = time.perf_counter_ns() - начало_коммита
        общий = Path(гит(ф.корень, 'rev-parse', '--git-common-dir').decode().strip())
        общий = (общий if общий.is_absolute() else ф.корень / общий).resolve()
        области = (ф.корень, общий, ф.состояние, ф.п.объекты)
        начало_снимков = time.perf_counter_ns()
        до_повтора = [полный_снимок(область) for область in области]
        снимки_наносекунды = time.perf_counter_ns() - начало_снимков
        повтор = вызвать('применить', план, выбор)
        начало_снимков = time.perf_counter_ns()
        assert до_повтора == [полный_снимок(область) for область in области]
        снимки_наносекунды += time.perf_counter_ns() - начало_снимков

        assert повтор['без_повторных_эффектов'] and процессы[-1]['эффекты_Гит'] == 0
        assert снимок_служебных() == служебные_до
        assert [п.read_bytes() for п in конфиги] == конфиги_до
        результаты.append({'повтор': номер, 'вариант': порядок[номер - 1],
            'пара': (номер + 1) // 2 if параметры.парный_C5 else None,
            'начало_цикла_эпоха_наносекунды': начало_цикла, 'конец_цикла_эпоха_наносекунды': time.time_ns(),
            'цикл_с_подготовкой_и_внешними_проверками_наносекунды': time.perf_counter_ns() - монотонное_начало_цикла
                + (подготовка_истории if номер == 1 else 0),
            'наблюдение_снимков_повтора_наносекунды': снимки_наносекунды,
            'код_подготовки_sha256': hashlib.sha256(субъект(номер).read_bytes()).hexdigest(),
            'полный_выбранный_путь_наносекунды': sum(п['длительность_целого_процесса_наносекунды'] for п in процессы) + выбор_подготовка,
            'подготовка_наносекунды': подготовка, 'выбор_наносекунды': выбор_подготовка,
            'предмет': план['предмет'], 'объекты': план['объекты'],
            'отсутствующих_деревьев': len(план['отсутствующие_деревья']),
            'посторонний_коммит_наносекунды': посторонний_коммит,
            'replay_области_неизменны': True, 'служебные_метки': служебные_до,
            'служебные_неизменны': True, 'штатная_конфигурация': bool(служебные),
            'сценарий_конфигурации': сценарий, 'конфигурации_неизменны': True, 'процессы': процессы})
    assert all(э['предмет'] == результаты[0]['предмет'] and э['объекты'] == результаты[0]['объекты'] for э in результаты)
    assert ожидаемый_предмет is None or ожидаемый_предмет == результаты[0]['предмет']
    assert hashlib.sha256(СУБЪЕКТ.read_bytes()).hexdigest() == исходники[СУБЪЕКТ.name]
    документ = {'схема': 'fum.профиль-подготовки-кандидата.' + str(параметры.версия),
        'версия_подготовки': параметры.версия, 'общая_база': параметры.общая_база, 'основа': ф.м.ОСНОВА_КОДА,
        'контур_кода': ф.м.КОНТУР_КОДА, 'исходники': исходники,
        'парный_C5': параметры.парный_C5, 'порядок': порядок,
        'фон': 'По допуску ROOT v135 на этом Mac жив отдельный B APPLY4 PID40041 на frozen C5. Его входы не открывались, непрерывность здесь не измеряется.',
        'покрытие': 'ЧТЕНИЯ покрывают собственные прочитать и завершённые прежние run. Новый пакетный_канал_деревьев покрывает собственный streaming stdout/stderr/stdin отдельно; его нельзя складывать с audit-процессами. Байты вложенного C572 os.read не покрыты. Память baseline отсутствует, это не ноль. Новый пик памяти относится только к процессу Python. Логические размеры и транспортные байты не складываются.',
        'исполнители': {'python': {'версия': sys.version.split()[0], 'sha256': ф.предвыбор['python']['sha256']},
            'git': {'версия': гит(ф.корень, '--version').decode().strip(), 'sha256': ф.предвыбор['гит']['sha256']}},
        'ограничения': 'Малый синтетический корпус. Setup и независимый выбор исключены из фаз. Кэш ОС не сброшен. CPU процесса и CPU дочерних процессов раздельны; вложенные wall не суммируются. Файловые read и байты stdout Git наблюдаются раздельно; это не физический дисковый I/O. Метрики вложенных фаз не суммируются с целым процессом. Legacy RED и новый GREEN имеют разные исходы и не доказывают ускорение. Production/Creator/приёмка B не измерены.',
        'решение_об_оптимизации': 'Повторные защиты не сокращать. Конечные замки и оба слоя конфигурации необходимы для корректности. Разобранные конфигурации переиспользуются только в пределах контекста по SHA повторно прочитанных сырых байтов. Ускорение без равного успешного исхода не заявляется; решение о дальнейших изменениях принимается по измерениям трёх свежих циклов.',
        'повторы': результаты}
    параметры.выход.parent.mkdir(parents=True, exist_ok=True)
    with параметры.выход.open('xb') as поток:
        поток.write(ф.м.байты(документ))
    print(json.dumps({'повторов': len(результаты), 'объекты': результаты[0]['объекты']}, ensure_ascii=False))


if __name__ == '__main__':
    выполнить()

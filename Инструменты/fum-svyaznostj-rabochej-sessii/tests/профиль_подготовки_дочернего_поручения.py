def наблюдать_позднюю_привязку():
    """Реальная конечная Git-фикстура; вложенные интервалы не суммируются."""
    import test_поздней_привязки_журнала as поздние
    корень=Path(__file__).resolve().parents[3]
    пути=[Path(__file__),Path(поздние.__file__),Path(генератор.__file__),
        корень/'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/поздняя_привязка_журнала.py',
        корень/'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/основание_двусторонней_координации.py']
    до={п.relative_to(корень).as_posix():генератор.хэш(п.read_bytes()) for п in пути}
    интервалы=[];открытые={};источники=[];счётчики={};байты={};строки={};задействованные=set()
    префикс=str(корень/'Инструменты')+'/'
    имена={'_исходное','_план_начала','_подготовить','применить','_пины_контура',
        '_прочитать_поток','прочитать_живой_префикс','_штатный_снимок_постановки','_исходное_время'}
    предыдущий=sys.getprofile()
    def профиль(кадр,событие,результат):
        имя_файла=кадр.f_code.co_filename
        if not имя_файла.startswith(префикс): return
        if имя_файла.endswith('.py'): задействованные.add(имя_файла)
        имя=кадр.f_code.co_name
        if имя not in имена: return
        файл=Path(имя_файла)
        ключ=файл.relative_to(корень).as_posix()+':'+имя
        if событие=='call':
            открытые[id(кадр)]=(time.perf_counter_ns(),ключ,len(открытые))
            счётчики[ключ]=счётчики.get(ключ,0)+1
        elif событие=='return':
            начало,ключ,вложенность=открытые.pop(id(кадр))
            интервалы.append({'граница':ключ,'наносекунды':time.perf_counter_ns()-начало,
                'вложенность':вложенность,'результат_возвращён':результат is not None})
            if имя=='_прочитать_поток' and isinstance(результат,tuple) and isinstance(результат[0],dict):
                индекс=результат[0]
                число=результат[1].get('прочитано_байтов')
                if type(число) is int: байты[ключ]=байты.get(ключ,0)+число
                число=результат[1].get('разобрано_строк')
                if type(число) is int: строки[ключ]=строки.get(ключ,0)+число
                источники.append({'граница':индекс.get('граница'),'sha256':индекс.get('sha256'),
                    'экземпляры':[э['экземпляр'] for э in индекс.get('сообщения',[])]})
    пример=поздние.КомпозицияПозднегоЖурнала()
    начало=time.perf_counter_ns();sys.setprofile(профиль)
    try:
        пример.test_настоящая_композиция_от_приглашения_до_штатного_входа_и_повтора()
        конец=time.perf_counter_ns()
    finally:
        sys.setprofile(предыдущий);пример.doCleanups()
    генератор.требовать(до=={п.relative_to(корень).as_posix():генератор.хэш(п.read_bytes()) for п in пути},
        'код профиля изменился во время наблюдения')
    return {'схема':'fum.профиль-поздней-привязки.1','календарные_наносекунды':конец-начало,
        'стадии':{'основание':'_исходное','папка':'_план_начала','композиция':'_подготовить','установка':'применить'},
        'интервалы':интервалы,'проходы':счётчики,'логические_байты_читателей':байты,'разобрано_строк':строки,
        'снимки_входов':источники,'исходники_sha256':до,
        'исполненный_контур_sha256':{п.relative_to(корень).as_posix():генератор.хэш(п.read_bytes()) for п in sorted(map(Path,задействованные)) if п.is_file()},
        'условия':{'версия_питона':sys.version,'платформа':platform.platform(),
            'закрепление_лингвистического_набора':генератор.гит(корень,'rev-parse','HEAD:Зависимости/LinguisticKit')},
        'граница':'Одна настоящая автономная Git-фикстура, собственный CLI времени и завершённые start/ACT/.7/v4/repeat. '
            'Календарь включает setup и Git-процессы; cleanup и сериализация исключены. Интервалы вложены и не суммируются. '
            'Метки sys.setprofile входят в длительности; кэш ОС не очищается. Логические байты Python-читателя не равны физическому I/O. '
            'Живой ROOT, Desktop-писатель, ready/commit/delivery и атомарность не проверены. Ускорение не заявлено.'}


def наблюдать(вариант, полные_пересверки=False):
    начало = time.perf_counter_ns(); пример = примеры.ПодготовкаПоручения()
    счётчики = {}; байтов = {}; незавершённые = {}; предыдущий = sys.getprofile()
    имена = {'_прочитать_снимок', '_прочитать_поток', '_сверить_снимок',
        'прочитать_начало_источника', 'прочитать_нативное_поручение', 'сверить_источник'}
    def профиль(кадр, событие, результат):
        имя = кадр.f_code.co_name
        if имя not in имена: return
        if событие == 'call':
            счётчики[имя] = счётчики.get(имя,0)+1; незавершённые[id(кадр)] = имя
        elif событие == 'return':
            незавершённые.pop(id(кадр),None)
            if isinstance(результат,dict) and isinstance(результат.get('профиль'),dict):
                число = результат['профиль'].get('прочитано_байтов')
                if type(число) is int: байтов[имя] = байтов.get(имя,0)+число
    sys.setprofile(профиль)
    try:
        пример.setUp(); конец_подготовки = time.perf_counter_ns()
        ф = пример.ф; м = ф.м; действия = []; повторов = 0
        if вариант == 'генератор':
            план = генератор.построить_план(пример.вход); действия.append('preview')
            файл = пример.выходы/'план.json'; файл.write_bytes(генератор.байты(план)); файл.chmod(0o400)
            генератор.применить(пример.вход, файл, генератор.хэш(файл.read_bytes()),полные_пересверки=полные_пересверки); действия.append('apply')
            вход = план['технические_входы']['фасад']; п = план['технические_входы']['коммит']
            ручные_поля = ['решение','писатель','корень','каталог_выходов','источник_модели','источники','область_писателя']
        else:
            # Независимая ручная композиция из полей прежней настоящей фикстуры.
            пост = пример.решение['постановка']; (ф.корень/пост['путь']).write_text(пост['текст'])
            п = ф.п; п['исходный_коммит'] = ф.ф.гит('rev-parse','HEAD').strip(); п['родители'] = [п['исходный_коммит']]
            п['разрешённые_цели'].append(пост['путь'])
            ф.сохранить('вход-root.json',п); ф.сохранить('разрешение-root.json',п['разрешённые_цели'])
            ф.наполнение['разрешение']['sha256'] = генератор.хэш(ф.разрешение.read_bytes())
            ф.сохранить('наполнение-root.json',ф.наполнение); вход = ф.вход
            вход['обновления']=['журнал','recency']
            ручные_поля = list(п)+list(вход)
            действия.extend(['составить постановку','перенести параметры коммита','перенести фасад','пересвязать разрешение'])
        конец_композиции = time.perf_counter_ns()
        план_этапа = м.построить_план(вход); хэш_плана = м.хэш(м.байты(план_этапа))
        итог = (прежний.ручной_ROOT_цикл(вход,план_этапа,хэш_плана,ф.запуск_CLI) if вариант=='ручной'
            else м.выполнить(вход,план_этапа,хэш_плана))
        генератор.требовать(итог['код']==0,'реальный отказ подготовки до готовности')
        готовность = м.коммит.готовность.прочитать(м.коммит.готовность.путь_этапа(п),п)
        генератор.требовать(готовность is not None,'готовность не подтверждена')
        конец = time.perf_counter_ns()
        return {'вариант':вариант, 'календарные_наносекунды':конец-начало,
            'подготовка_наносекунды':конец_подготовки-начало,
            'композиция_наносекунды':конец_композиции-конец_подготовки,
            'проверки_до_готовности_наносекунды':конец-конец_композиции,
            'действия_корня':действия, 'технические_поля_композиции':ручные_поля,
            'отказы':0,'повторы':повторов,'проходы_именованных_читателей':счётчики,
            'логические_байты_наблюдаемых_читателей':байтов,
            'основа':{'команды':[генератор.хэш(т.encode()) for т in ф.сообщения],
                'постановка':генератор.хэш(пример.решение['постановка']['текст'].encode()),
                'тест':генератор.хэш(ф.тест.read_bytes())},
            'готовность_sha256':генератор.хэш(м.коммит.готовность.путь_этапа(п).read_bytes())}
    finally:
        sys.setprofile(предыдущий); пример.doCleanups()


def главная():
    р = argparse.ArgumentParser(description=__doc__,allow_abbrev=False)
    р.add_argument('--выход',required=True); р.add_argument('--раунды',type=int,default=1)
    р.add_argument('--полные-пересверки',action='store_true')
    р.add_argument('--поздняя-привязка',action='store_true')
    п = р.parse_args(); генератор.требовать(п.раунды in (1,3),'нужен один либо три парных раунда')
    выход = Path(п.выход); генератор.требовать(выход.is_absolute() and выход==выход.resolve() and not os.path.lexists(выход),'нужен новый абсолютный выход')
    наблюдения = []
    for номер in range(0 if п.поздняя_привязка else п.раунды):
        пара = [наблюдать(в,п.полные_пересверки) for в in (('ручной','генератор') if номер%2==0 else ('генератор','ручной'))]
        генератор.требовать(пара[0]['основа']==пара[1]['основа'],'непарная смысловая основа')
        наблюдения.extend(пара)
    результат = {'наблюдения':наблюдения,'граница':'Календарь включает setup, композицию и реальные проверки до ready; интервалы разделяют его без повторного сложения. Cleanup, сериализация выхода, доставка и живое ожидание исключены. Действия и поля описывают операции воспроизводимого сценария, а не измеренные действия человека. Счётчики отражают Python-процессы профиля; subprocess reader и физический I/O неизвестны. Кэш ОС не очищается; ускорение заранее не утверждается.'}
    выход.parent.mkdir(parents=True,exist_ok=True)
    результат['полные_пересверки']=п.полные_пересверки
    if п.поздняя_привязка: результат=наблюдать_позднюю_привязку()
    дескриптор = os.open(выход,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
    with os.fdopen(дескриптор,'wb') as поток: поток.write(генератор.байты(результат))
    print(json.dumps({'пар':п.раунды,'наблюдений':len(наблюдения)},ensure_ascii=False)); return 0


if __name__ == '__main__':
    raise SystemExit(главная())

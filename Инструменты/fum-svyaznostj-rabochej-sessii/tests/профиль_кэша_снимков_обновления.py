def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def байты(данные):
    return (
        json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    ).encode("utf-8")


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def сохранить(путь, данные, режим=0o600):
    данные = данные if isinstance(данные, bytes) else байты(данные)
    флаги = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    флаги |= getattr(os, "O_NOFOLLOW", 0)
    with os.fdopen(os.open(путь, флаги, режим), "wb") as файл:
        os.fchmod(файл.fileno(), режим)
        файл.write(данные)
        файл.flush()
        os.fsync(файл.fileno())


def окружение():
    результат = {
        имя: значение for имя, значение in os.environ.items()
        if not имя.startswith("GIT_")
    }
    результат.update(
        GIT_OPTIONAL_LOCKS="0",
        GIT_CONFIG_NOSYSTEM="1",
        GIT_CONFIG_GLOBAL=os.devnull,
        PYTHONDONTWRITEBYTECODE="1",
    )
    return результат


def гит(корень, *аргументы, вход=None):
    итог = subprocess.run(
        ["git", "-C", str(корень), *аргументы],
        input=вход, capture_output=True, env=окружение(),
    )
    требовать(итог.returncode == 0, "Git-чтение или подготовка фикстуры отказали")
    return итог.stdout


def метаданные(состояние):
    return [
        состояние.st_dev, состояние.st_ino,
        stat.S_IMODE(состояние.st_mode), состояние.st_size,
        состояние.st_mtime_ns, состояние.st_ctime_ns,
    ]


def обычный_файл(путь, режим=None):
    требовать(путь.is_absolute(), "нужен абсолютный путь")
    for часть in [*reversed(путь.parents), путь]:
        требовать(not часть.is_symlink(), "символическая ссылка во входе")
    состояние = путь.lstat()
    требовать(stat.S_ISREG(состояние.st_mode), "нужен обычный файл")
    требовать(состояние.st_uid == os.getuid(), "чужой владелец файла")
    if режим is not None:
        требовать(
            stat.S_IMODE(состояние.st_mode) == режим,
            "неверный режим файла",
        )
    return состояние


def снимок_дерева(корень):
    файлы, ограда = {}, {}
    def ошибка_обхода(ошибка):
        raise ошибка

    for каталог, каталоги, имена in os.walk(корень, followlinks=False, onerror=ошибка_обхода):
        каталоги[:] = sorted(имя for имя in каталоги if имя != ".git")
        путь = Path(каталог)
        относительный = путь.relative_to(корень).as_posix()
        состояние = путь.lstat()
        требовать(stat.S_ISDIR(состояние.st_mode), "необычный каталог")
        ограда[относительный] = метаданные(состояние)
        for имя in каталоги:
            требовать(
                stat.S_ISDIR((путь / имя).lstat().st_mode),
                "ссылка или необычный вложенный каталог",
            )
        for имя in sorted(имена):
            файл = путь / имя
            до = обычный_файл(файл)
            данные = файл.read_bytes()
            требовать(
                метаданные(до) == метаданные(файл.lstat()),
                "файл изменился при снятии manifest",
            )
            цель = файл.relative_to(корень).as_posix()
            файлы[цель] = {
                "sha256": хэш(данные),
                "режим": stat.S_IMODE(до.st_mode),
                "байты": len(данные),
            }
            ограда[цель] = метаданные(до)
    return {
        "файлы": файлы,
        "ограда_метаданных_sha256": хэш(байты(ограда)),
    }


def снимок_входа(корень):
    результат = снимок_дерева(корень)
    индекс = Path(гит(
        корень, "rev-parse", "--path-format=absolute", "--git-path", "index",
    ).decode().strip())
    до = обычный_файл(индекс)
    данные = индекс.read_bytes()
    требовать(
        метаданные(до) == метаданные(индекс.lstat()),
        "индекс изменился при чтении",
    )
    результат.update(
        HEAD=гит(корень, "rev-parse", "HEAD").decode().strip(),
        ref=гит(корень, "symbolic-ref", "HEAD").decode().strip(),
        индекс_sha256=хэш(данные),
        индекс_метаданные_sha256=хэш(байты(метаданные(до))),
    )
    return результат


def извлечь_исходники(корень):
    требовать(
        гит(корень, "rev-parse", БАЗА + "^{commit}").decode().strip() == БАЗА,
        "не подтверждён точный коммит C",
    )
    записи = []
    for строка in гит(корень, "ls-tree", "-rz", БАЗА, "--", "Инструменты").split(b"\0"):
        if not строка:
            continue
        описание, имя = строка.split(b"\t", 1)
        имя = имя.decode("utf-8")
        if not имя.endswith(".py"):
            continue
        режим, тип, объект = описание.decode("ascii").split()
        требовать(
            тип == "blob" and режим in {"100644", "100755"},
            "необычный Python-источник в C",
        )
        записи.append((имя, объект))
    требовать(any(имя == ФАСАД for имя, _ in записи), "нет фасада в C")
    поток = io.BytesIO(гит(
        корень, "cat-file", "--batch",
        вход="".join(объект + "\n" for _, объект in записи).encode("ascii"),
    ))
    результат = {}
    for имя, объект in записи:
        заголовок = поток.readline().decode("ascii").strip().split()
        требовать(
            len(заголовок) == 3 and заголовок[:2] == [объект, "blob"],
            "неверный ответ cat-file",
        )
        размер = int(заголовок[2])
        данные = поток.read(размер)
        требовать(
            len(данные) == размер and поток.read(1) == b"\n",
            "неполный blob C",
        )
        результат[имя] = данные
    требовать(поток.read() == b"", "лишний хвост cat-file")
    return результат


def установить_исходники(корень, исходники):
    корень.mkdir(mode=0o700)
    for имя, данные in исходники.items():
        путь = корень / имя
        путь.parent.mkdir(parents=True, exist_ok=True)
        сохранить(путь, данные, 0o400)



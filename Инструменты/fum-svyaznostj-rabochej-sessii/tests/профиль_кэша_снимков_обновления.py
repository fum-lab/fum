def конкуренция():
    результат = {}
    try:
        результат["нагрузка"] = list(os.getloadavg())
        вывод = subprocess.check_output(
            ["ps", "-axo", "stat=,%cpu="], text=True,
        )
        состояния = [строка.split() for строка in вывод.splitlines()]
        состояния = [строка for строка in состояния if len(строка) == 2]
        нагрузки = [float(строка[1].replace(",", ".")) for строка in состояния]
        результат.update(
            процессов=len(состояния),
            выполняющихся=sum(строка[0].startswith("R") for строка in состояния),
            сумма_загрузки_процессоров=sum(нагрузки),
            максимум_загрузки_процессора=max(нагрузки, default=0),
        )
    except (OSError, ValueError, subprocess.CalledProcessError) as ошибка:
        результат["неизвестно"] = type(ошибка).__name__
    return результат


def зависимости(корень, ожидаемые, наблюдатель):
    результат = {}
    префиксы = {Path(sys.prefix).resolve(), Path(sys.base_prefix).resolve()}
    for модуль in list(sys.modules.values()):
        имя = getattr(модуль, "__file__", None)
        if not имя:
            continue
        путь = Path(имя).resolve()
        if путь == наблюдатель:
            continue
        if путь.is_relative_to(корень):
            цель = путь.relative_to(корень).as_posix()
            требовать(цель in ожидаемые, "необъявленный собственный импорт")
            обычный_файл(путь, 0o400)
            результат[цель] = хэш(путь.read_bytes())
            требовать(
                результат[цель] == ожидаемые[цель],
                "дрейф импортированного собственного исходника",
            )
        else:
            требовать(
                any(путь.is_relative_to(префикс) for префикс in префиксы),
                "импорт вне закреплённого контура и интерпретатора",
            )
    требовать(ФАСАД in результат, "не наблюдён импорт фасада")
    return результат


def замер(модуль, корень, имя, номер):
    запись = {
        "обновление": имя, "порядок_снимка": номер,
        "наносекунды": {"пути": 0, "чтение": 0, "хэш": 0},
        "вызовы": {"пути": 0, "чтения": 0, "хэш": 0},
        "прочитано_байтов": 0, "хэшировано_байтов": 0,
        "перечисления": {},
    }
    глубина = [0]
    исходный_путь = модуль.коммит.охват.точный_путь
    исходное_чтение = Path.read_bytes
    исходное_перечисление = Path.iterdir
    исходный_хэш = модуль.хэш

    def проверить_путь(*аргументы, **параметры):
        начало = time.perf_counter_ns()
        глубина[0] += 1
        запись["вызовы"]["пути"] += 1
        try:
            return исходный_путь(*аргументы, **параметры)
        finally:
            глубина[0] -= 1
            запись["наносекунды"]["пути"] += time.perf_counter_ns() - начало

    def перечислить(путь):
        if глубина[0]:
            цель = путь.relative_to(корень).as_posix()
            запись["перечисления"][цель] = запись["перечисления"].get(цель, 0) + 1
        return исходное_перечисление(путь)

    def прочитать(путь):
        if not путь.is_relative_to(корень) or ".git" in путь.relative_to(корень).parts:
            return исходное_чтение(путь)
        начало = time.perf_counter_ns()
        try:
            данные = исходное_чтение(путь)
        finally:
            запись["наносекунды"]["чтение"] += time.perf_counter_ns() - начало
        запись["вызовы"]["чтения"] += 1
        запись["прочитано_байтов"] += len(данные)
        return данные

    def хэшировать(данные):
        начало = time.perf_counter_ns()
        try:
            return исходный_хэш(данные)
        finally:
            запись["наносекунды"]["хэш"] += time.perf_counter_ns() - начало
            запись["вызовы"]["хэш"] += 1
            запись["хэшировано_байтов"] += len(данные)

    результат = None
    with (
        mock.patch.object(модуль.коммит.охват, "точный_путь", проверить_путь),
        mock.patch.object(Path, "iterdir", перечислить),
        mock.patch.object(Path, "read_bytes", прочитать),
        mock.patch.object(модуль, "хэш", хэшировать),
    ):
        начало = time.perf_counter_ns()
        try:
            результат = модуль.снимок_обновления(корень, имя)
        except Exception as ошибка:
            запись["отказ"] = type(ошибка).__name__
        finally:
            запись["наносекунды"]["снимок"] = time.perf_counter_ns() - начало
    return запись, результат


def работник(план_файла, выход):
    план = json.loads(план_файла.read_bytes())
    итог = {"готов": False, "снимки": []}
    try:
        корень = Path(план["вход"])
        исходники = Path(план["исходники"])
        наблюдатель = Path(__file__).resolve()
        требовать(
            хэш(наблюдатель.read_bytes()) == план["наблюдатель_sha256"],
            "дрейф наблюдателя",
        )
        требовать(
            снимок_дерева(исходники) == план["ограда_исходников"],
            "дрейф сохранённых исходников",
        )
        sys.path.insert(0, str((исходники / ФАСАД).parent))
        модуль = importlib.import_module("подготовка_этапа_коммита")
        зависимости(исходники, план["исходники_sha256"], наблюдатель)
        исходный = план["снимок_входа"]
        for номер, имя in enumerate(
            ["журнал", "журнал", "журнал", "recency", "recency"], 1,
        ):
            требовать(снимок_входа(корень) == исходный, "дрейф до снимка")
            запись, результат = замер(модуль, корень, имя, номер)
            if результат is not None:
                запись["результат_sha256"] = хэш(байты(результат))
            итог["снимки"].append(запись)
            сохранить(выход.with_name(f"{выход.stem}-{номер}.json"), запись)
            требовать("отказ" not in запись, "снимок отказал")
            ожидаемые = {
                цель: {"sha256": сведения["sha256"], "режим": сведения["режим"]}
                for цель, сведения in исходный["файлы"].items()
                if цель.endswith(".md")
                and (имя == "recency" or цель.startswith("Журнал/"))
            }
            требовать(результат == ожидаемые, "снимок отличается от pinned manifest")
            количество = len(ожидаемые)
            объём = sum(исходный["файлы"][цель]["байты"] for цель in ожидаемые)
            требовать(
                запись["вызовы"] == {
                    "пути": количество, "чтения": количество, "хэш": количество,
                }
                and запись["прочитано_байтов"] == объём
                and запись["хэшировано_байтов"] == объём,
                "изменилось число файлов, чтений или байтов",
            )
            запись["результат_sha256"] = хэш(байты(результат))
            запись["файлов"] = количество
            требовать(снимок_входа(корень) == исходный, "дрейф после снимка")
        итог["зависимости"] = зависимости(
            исходники, план["исходники_sha256"], наблюдатель,
        )
        требовать(
            снимок_дерева(исходники) == план["ограда_исходников"],
            "дрейф исходников после замеров",
        )
        итог["вход_sha256"] = хэш(байты(исходный))
        итог["готов"] = True
    except Exception as ошибка:
        итог["отказ"] = (
            str(ошибка) if isinstance(ошибка, ValueError)
            else type(ошибка).__name__
        )
    сохранить(выход, итог)
    return 0 if итог["готов"] else 1


def профиль(корень, кандидат, хэш_кандидата, выход):
    корень = корень.resolve(strict=True)
    кандидат = кандидат.absolute()
    выход = выход.absolute()
    требовать(not кандидат.is_relative_to(корень), "candidate внутри checkout")
    требовать(not выход.is_relative_to(корень), "выход внутри checkout")
    состояние = обычный_файл(кандидат, 0o400)
    данные_кандидата = кандидат.read_bytes()
    требовать(хэш(данные_кандидата) == хэш_кандидата, "неверный candidate SHA")
    родитель = выход.parent.resolve(strict=True)
    требовать(родитель == выход.parent, "нефизический родитель выхода")
    требовать(
        родитель.stat().st_uid == os.getuid()
        and stat.S_IMODE(родитель.stat().st_mode) == 0o700
        and not os.path.lexists(выход),
        "нужен новый выход в собственном каталоге0700",
    )
    приватный = Path(tempfile.mkdtemp(prefix="кэш-снимков-", dir=родитель))
    наблюдатель = приватный / "наблюдатель.py"
    данные_наблюдателя = Path(__file__).read_bytes()
    сохранить(наблюдатель, данные_наблюдателя, 0o400)
    итог = {
        "схема": "fum.профиль-кэша-снимков.1",
        "готов": False, "база": БАЗА, "коммит_кандидата": None,
        "кандидат_sha256": хэш_кандидата,
        "наблюдатель_sha256": хэш(данные_наблюдателя),
        "интерпретатор": {
            "версия": sys.version,
            "реализация": platform.python_implementation(),
            "sha256": хэш(Path(sys.executable).resolve().read_bytes()),
        },
        "система": {
            "название": platform.system(),
            "выпуск": platform.release(),
            "архитектура": platform.machine(),
        },
        "наблюдения": [],
        "граница": (
            "12 свежих процессов ABBA×3; каждый: 3 журнал и 2 recency. "
            "Setup, импорт, manifest-сверки и сериализация вне таймеров. "
            "Предсверки читают вход целиком; кэш ОС не сбрасывается. "
            "Вложенные интервалы не складываются с временем снимка."
        ),
        "ускорение_фасада": "unknown",
    }
    try:
        исходники = извлечь_исходники(корень)
        варианты = {"A": исходники, "B": {**исходники, ФАСАД: данные_кандидата}}
        планы = {}
        вход = приватный / "вход"
        подготовить_фикстуру(вход)
        исходный = снимок_входа(вход)
        итог["снимок_входа"] = исходный
        итог["фасад_базы_sha256"] = хэш(исходники[ФАСАД])
        for вариант, данные in варианты.items():
            дерево = приватный / вариант
            установить_исходники(дерево, данные)
            планы[вариант] = {
                "вход": str(вход), "исходники": str(дерево),
                "снимок_входа": исходный,
                "ограда_исходников": снимок_дерева(дерево),
                "исходники_sha256": {имя: хэш(текст) for имя, текст in данные.items()},
                "наблюдатель_sha256": хэш(данные_наблюдателя),
            }
        общие, результаты = None, {}
        for порядок, вариант in enumerate(["A", "B", "B", "A"] * 3, 1):
            требовать(снимок_входа(вход) == исходный, "дрейф между элементами ABBA")
            план = приватный / f"план-{порядок}.json"
            результат = приватный / f"результат-{порядок}.json"
            сохранить(план, планы[вариант])
            наблюдение = {
                "порядок": порядок, "блок": (порядок - 1) // 4 + 1,
                "вариант": вариант, "конкуренция_до": конкуренция(),
            }
            итог["наблюдения"].append(наблюдение)
            процесс = subprocess.run(
                [sys.executable, "-I", "-S", "-B", str(наблюдатель),
                 "--работник", "--план", str(план), "--результат", str(результат)],
                cwd=приватный, env=окружение(), capture_output=True,
            )
            сохранить(приватный / f"stdout-{порядок}.bin", процесс.stdout)
            сохранить(приватный / f"stderr-{порядок}.bin", процесс.stderr)
            наблюдение.update(
                код=процесс.returncode, конкуренция_после=конкуренция(),
                stdout_sha256=хэш(процесс.stdout), stderr_sha256=хэш(процесс.stderr),
            )
            if результат.exists():
                данные = результат.read_bytes()
                запись = json.loads(данные)
                требовать(данные == байты(запись), "неканонический результат worker")
                наблюдение["измерение"] = запись
            else:
                наблюдение["измерение"] = {
                    "готов": False,
                    "снимки": [
                        json.loads(файл.read_bytes())
                        for номер in range(1, 6)
                        if (файл := результат.with_name(
                            f"{результат.stem}-{номер}.json",
                        )).exists()
                    ],
                }
            требовать(
                процесс.returncode == 0
                and наблюдение["измерение"].get("готов") is True,
                "работник профиля отказал",
            )
            запись = наблюдение["измерение"]
            зависимости_общие = {
                имя: значение for имя, значение in запись["зависимости"].items()
                if имя != ФАСАД
            }
            if общие is None:
                общие = зависимости_общие
            требовать(зависимости_общие == общие, "различаются общие импортированные SHA")
            для_сравнения = [
                (снимок["обновление"], снимок["результат_sha256"],
                 снимок["файлов"], снимок["прочитано_байтов"],
                 снимок["хэшировано_байтов"], снимок["вызовы"])
                for снимок in запись["снимки"]
            ]
            if not результаты:
                результаты["ожидаемые"] = для_сравнения
            требовать(
                для_сравнения == результаты["ожидаемые"],
                "различаются результаты A/B",
            )
            требовать(снимок_входа(вход) == исходный, "дрейф после элемента ABBA")
            требовать(
                метаданные(обычный_файл(кандидат, 0o400)) == метаданные(состояние)
                and кандидат.read_bytes() == данные_кандидата,
                "дрейф исходного immutable candidate",
            )
        итог["общие_импортированные_sha256"] = общие
        итог["медианы_наносекунды"] = {
            имя: {
                вариант: {
                    стадия: int(statistics.median([
                        снимок["наносекунды"][стадия]
                        for наблюдение in итог["наблюдения"]
                        if наблюдение["вариант"] == вариант
                        for снимок in наблюдение["измерение"]["снимки"]
                        if снимок["обновление"] == имя
                    ]))
                    for стадия in ("снимок", "пути", "чтение", "хэш")
                }
                for вариант in ("A", "B")
            }
            for имя in ("журнал", "recency")
        }
        требовать(
            Path(__file__).read_bytes() == данные_наблюдателя,
            "дрейф исходника измерителя",
        )
        итог["готов"] = True
    except Exception as ошибка:
        итог["отказ"] = (
            str(ошибка) if isinstance(ошибка, ValueError)
            else type(ошибка).__name__
        )
    сохранить(выход, итог)
    return 0 if итог["готов"] else 1


def главная():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--корень", type=Path)
    парсер.add_argument("--кандидат", type=Path)
    парсер.add_argument("--sha256-кандидата", dest="хэш_кандидата")
    парсер.add_argument("--выход", type=Path)
    парсер.add_argument("--работник", action="store_true")
    парсер.add_argument("--план", type=Path)
    парсер.add_argument("--результат", type=Path)
    параметры = парсер.parse_args()
    if параметры.работник:
        требовать(
            параметры.план is not None and параметры.результат is not None
            and all(значение is None for значение in (
                параметры.корень, параметры.кандидат,
                параметры.хэш_кандидата, параметры.выход,
            )),
            "неверные поля работника",
        )
        return работник(параметры.план, параметры.результат)
    требовать(
        all(значение is not None for значение in (
            параметры.корень, параметры.кандидат,
            параметры.хэш_кандидата, параметры.выход,
        ))
        and параметры.план is None and параметры.результат is None,
        "неверные поля профиля",
    )
    return профиль(
        параметры.корень, параметры.кандидат,
        параметры.хэш_кандидата, параметры.выход,
    )


if __name__ == "__main__":
    raise SystemExit(главная())

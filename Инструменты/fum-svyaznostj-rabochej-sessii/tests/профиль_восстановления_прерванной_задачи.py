def снимок_файлов(корень):
    return {str(путь.relative_to(корень)): hashlib.sha256(путь.read_bytes()).hexdigest()
        for путь in корень.rglob("*") if путь.is_file()}


def измерить(сценарий, повторы):
    исходный = снимок_файлов(сценарий.папка)
    замеры = []
    прежний_запуск = subprocess.run
    эталон = None
    for _ in range(повторы):
        обращения = {"процессов_git": 0, "байтов_stdout_git": 0}
        def запуск(*аргументы, **параметры):
            команда = аргументы[0] if аргументы else параметры.get("args", [])
            assert команда and Path(команда[0]).name == "git", "Preview запустил посторонний процесс"
            обращения["процессов_git"] += 1
            результат = прежний_запуск(*аргументы, **параметры)
            if результат.stdout is not None:
                обращения["байтов_stdout_git"] += len(результат.stdout.encode() if isinstance(результат.stdout, str) else результат.stdout)
            return результат
        профиль = {}
        tracemalloc.start()
        начало = time.monotonic_ns()
        with patch.object(subprocess, "run", запуск):
            результат = сценарий.вычислить(профиль)
        время = time.monotonic_ns() - начало
        _, пик = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        assert результат["допуск_эффекта"] is False
        assert not результат["завершение_всей_работы_доказано"]
        if эталон is None:
            эталон = результат["действие"]
        assert эталон == результат["действие"], "Решение изменилось при одинаковом входе"
        assert исходный == снимок_файлов(сценарий.папка), "Preview изменил фикстуру"
        замеры.append({**профиль, **обращения, "измерение_наносекунды": время, "пик_python_байтов": пик})
    return {"замеры": замеры, "медиана_наносекунды": statistics.median(з["измерение_наносекунды"] for з in замеры),
        "медиана_сигнал_наносекунды": statistics.median(з["сигнал_наносекунды"] for з in замеры),
        "решение": эталон["вид"], "задача": эталон["задача"], "фикстура_не_изменена": True}


def измерить_писателя(сценарий, повторы):
    исходный = {имя: снимок_файлов(каталог) for имя, каталог in
        (("канон", сценарий.репо), ("писатель", сценарий.дерево), ("снимки", сценарий.снимки))}
    результаты = {"первый_эффект": [], "сверка_повтора": []}
    прежний_запуск = subprocess.run
    for повтор in range(повторы):
        сценарий.хранилище = сценарий.папка / ("намерение-" + str(повтор))
        сценарий.хранилище.mkdir(mode=0o700)
        for вариант, ожидаемые_отправки in (("первый_эффект", 1), ("сверка_повтора", 0)):
            обращения = {"процессов_git": 0, "байтов_stdout_git": 0}
            def запуск(*аргументы, **параметры):
                команда = аргументы[0] if аргументы else параметры.get("args", [])
                assert команда and Path(команда[0]).name == "git", "Посторонний процесс"
                обращения["процессов_git"] += 1
                результат = прежний_запуск(*аргументы, **параметры)
                if результат.stdout is not None:
                    обращения["байтов_stdout_git"] += len(результат.stdout.encode() if isinstance(результат.stdout, str) else результат.stdout)
                return результат
            адаптер = писатель.ТестовыйАдаптер([сценарий.наблюдение])
            профиль = {}
            tracemalloc.start(); начало = time.monotonic_ns()
            with patch.object(subprocess, "run", запуск):
                результат = сценарий.восстановить(адаптер, профиль)
            время = time.monotonic_ns() - начало
            _, пик = tracemalloc.get_traced_memory(); tracemalloc.stop()
            assert результат["действие"] == "сверить исход" and not результат["live_send"]
            assert len(адаптер.отправки) == профиль["тестовых_отправок"] == ожидаемые_отправки
            assert not результат["завершение_всей_работы_доказано"]
            результаты[вариант].append({**профиль, **обращения, "измерение_наносекунды": время,
                "пик_python_байтов": пик, "чтений_адаптера": адаптер.чтения})
        assert len(list(сценарий.хранилище.glob("*.json"))) == 1
        assert not list(сценарий.хранилище.glob("*.lock"))
    assert исходный == {имя: снимок_файлов(каталог) for имя, каталог in
        (("канон", сценарий.репо), ("писатель", сценарий.дерево), ("снимки", сценарий.снимки))}
    return {имя: {"замеры": замеры,
        "медиана_наносекунды": statistics.median(з["измерение_наносекунды"] for з in замеры),
        "тестовых_отправок": sum(з["тестовых_отправок"] for з in замеры),
        "checkout_и_источники_не_изменены": True} for имя, замеры in результаты.items()}


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", required=True, type=Path)
    разбор.add_argument("--повторы", type=int, default=3)
    параметры = разбор.parse_args()
    if not 1 <= параметры.повторы <= 10:
        разбор.error("нужно от 1 до 10 повторов")
    исходники = [Path(__file__).resolve(), Path(__file__).resolve().with_name("test_восстановление_прерванной_задачи.py"),
        Path(__file__).resolve().parents[1] / "scripts/восстановление_прерванной_задачи.py",
        Path(__file__).resolve().parents[1] / "scripts/восстановление_писателя.py"]
    исходники_sha = {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in исходники}
    with tempfile.TemporaryDirectory(prefix="fum-preview-профиль-") as временное:
        папка = Path(временное).resolve()
        обычная = папка / "обычная"; обычная.mkdir()
        сценарий = Сценарий(обычная)
        результаты = {"без_доставки": измерить(сценарий, параметры.повторы)}
        доставка = папка / "доставка"; доставка.mkdir()
        ф = Фикстура(доставка)
        назначение = назначить(ф)
        план = доставка_план.построить_план(ф.описание, [str(ф.цель)], ф.владельцы, назначение=назначение)
        сценарий.вход["исполнители"][0]["доставка"] = {"план": план, "владельцы": ф.владельцы}
        сценарий.изменить(результат={"состояние": "принят", "источник": сценарий.сохранить("принято.md", b"accepted\n")}, план_доставки=план["идентификатор"])
        результаты["с_доставкой"] = измерить(сценарий, параметры.повторы)
        assert результаты["с_доставкой"]["решение"] == "доставить принятый срез"
        разные = папка / "независимые"; разные.mkdir()
        независимый = Сценарий(разные)
        независимый.независимые_постановки()
        результаты["независимые_постановки"] = измерить(независимый, параметры.повторы)
        assert результаты["независимые_постановки"]["решение"] == "приёмка поставки"
        assert результаты["независимые_постановки"]["задача"] == ДРУГАЯ
        писатель_папка = папка / "первый-эффект"; писатель_папка.mkdir()
        результаты_писателя = измерить_писателя(СценарийПисателя(писатель_папка), параметры.повторы)
    assert исходники_sha == {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in исходники}
    результат = {"схема": "fum.профиль-предпросмотра-продолжения.3", "варианты": результаты,
        "писатель": результаты_писателя, "исходники_sha256": исходники_sha,
        "граница": "Установка фикстуры и сверка файлов исключены. time.monotonic_ns; tracemalloc учитывает Python, не дочерний Git. Байты явных источников и stdout Git раздельны; это не весь ввод ОС. Наблюдение, хранилище и тестовая отправка вложены в общее время и не суммируются с ним. Свежесть имитируется управляемым адаптером, живой JSONL/API не читается. Повтор не отправляет; пишет только собственное приватное намерение вне checkout.",
        "решение_об_оптимизации": "Сохранить канонические читатели и повторную сверку: на конечной фикстуре нет доказательства, что новый кэш сохранит актуальность дешевле. Общего ускорения FUM не заявлено."}
    параметры.выход.parent.mkdir(parents=True, exist_ok=True)
    with параметры.выход.open("xb") as файл:
        файл.write(байты(результат))
    print(json.dumps({"схема": результат["схема"], "варианты": {имя: {ключ: значение for ключ, значение in замер.items() if ключ != "замеры"} for имя, замер in результаты.items()},
        "писатель": {имя: {к: з for к, з in замер.items() if к != "замеры"} for имя, замер in результаты_писателя.items()}}, ensure_ascii=False))


if __name__ == "__main__":
    выполнить()

"""Три настоящие пары создания и точного повтора; подготовка вне таймеров."""
import argparse
import cProfile
import contextlib
import hashlib
import json
import os
from pathlib import Path
import platform
import statistics
import subprocess
import time
from unittest import mock

import test_создание_коммита as база
import типизированная_контрольная_точка as фасад
import профиль_типизированной_контрольной_точки as манифест

КОРЕНЬ = Path(__file__).resolve().parents[3]


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def снимок(ф):
    пути = {'квитанция': Path(ф.параметры['квитанция']),
            'готовность': база.коммит.готовность.путь_этапа(ф.параметры),
            'индекс': ф.корень / '.git/index', 'источник': ф.источник,
            'подготовка': Path(ф.параметры['подготовка']),
            'сообщение': Path(ф.параметры['сообщение']),
            'курсор': Path(ф.параметры['кэш_модели'])}
    return {'файлы_sha256': {имя: хэш(путь.read_bytes()) for имя, путь in пути.items()},
            'голова': ф.гит('rev-parse', 'HEAD').strip(),
            'ветка': ф.гит('symbolic-ref', 'HEAD').strip(),
            'stage0_sha256': хэш(ф.гит('ls-files', '--stage').encode())}


def измерить():
    имена = subprocess.check_output(['git', '-C', str(КОРЕНЬ), 'ls-files', '--cached', '--others',
        '--exclude-standard', '-z', '--', 'Инструменты/**/*.py'],
        env={**os.environ, 'GIT_OPTIONAL_LOCKS': '0'}).split(b'\0')
    до = {КОРЕНЬ / имя.decode(): хэш((КОРЕНЬ / имя.decode()).read_bytes()) for имя in имена if имя}
    трасса = cProfile.Profile(); пары = []
    for номер in range(1, 4):
        ф = база.СозданиеКоммита()
        try:
            ф.setUp(); ф.готовить()
            вход = фасад.ВходКонтрольнойТочки.из_значений(ф.параметры['подготовка'], [база.ЗАПУСК])
            условия = {'исходник_байтов': ф.источник.stat().st_size,
                       'исходник_sha256': хэш(ф.источник.read_bytes()),
                       'подготовка_sha256': хэш(Path(ф.параметры['подготовка']).read_bytes()),
                       'сообщение_sha256': хэш(Path(ф.параметры['сообщение']).read_bytes())}
            шаги = []

            def замер(имя):
                счётчики = {'установки_квитанции': 0, 'байты_установок_квитанции': 0,
                            'создания_намерения': 0, 'другие_установки': 0,
                            'коммиты': 0, 'живой_допуск': 0}
                стадии = {}; читатели = []; чтения = []
                адрес = Path(ф.параметры['квитанция'])

                def обернуть_стадию(название, функция):
                    def вызвать(*аргументы, **именованные):
                        начало = time.perf_counter_ns()
                        try: return функция(*аргументы, **именованные)
                        finally: стадии.setdefault(название, []).append(time.perf_counter_ns() - начало)
                    return вызвать

                def обернуть_читателя(название, функция):
                    def вызвать(*аргументы, **именованные):
                        начало = time.perf_counter_ns(); результат = None
                        try:
                            результат = функция(*аргументы, **именованные); return результат
                        finally:
                            читатели.append({'читатель': название,
                                'наносекунды': time.perf_counter_ns() - начало,
                                'профиль': None if результат is None else результат['профиль']})
                    return вызвать

                установить = база.коммит.сообщения._установить
                сохранить = база.коммит.модели.сохранить_сообщение
                исходный_гит = база.коммит.гит; прочитать = база.коммит.прочитать
                допуск = фасад.ранний_допуск

                def установщик(путь, данные):
                    if Path(путь) == адрес:
                        счётчики['установки_квитанции'] += 1
                        счётчики['байты_установок_квитанции'] += len(данные)
                    else: счётчики['другие_установки'] += 1
                    return установить(путь, данные)

                def намерение(путь, данные):
                    if Path(путь) == адрес: счётчики['создания_намерения'] += 1
                    return сохранить(путь, данные)

                def гит(корень, *аргументы, **именованные):
                    if аргументы and аргументы[0] == 'commit': счётчики['коммиты'] += 1
                    return исходный_гит(корень, *аргументы, **именованные)

                def чтение(путь, **именованные):
                    данные = прочитать(путь, **именованные)
                    чтения.append({'вид': 'квитанция' if Path(путь) == адрес else 'другой вход', 'байты': len(данные)})
                    return данные

                def живой(*аргументы, **именованные):
                    счётчики['живой_допуск'] += 1
                    return допуск(*аргументы, **именованные)

                with contextlib.ExitStack() as контур:
                    for название in ('_зафиксировать_новую_квитанцию', 'восстановить',
                                      '_создать_проверенный_коммит', '_применить_автообзор'):
                        контур.enter_context(mock.patch.object(база.коммит, название,
                            side_effect=обернуть_стадию(название, getattr(база.коммит, название))))
                    for модуль, название, функция in ((база.коммит.сообщения, '_установить', установщик),
                            (база.коммит.модели, 'сохранить_сообщение', намерение),
                            (база.коммит, 'гит', гит), (база.коммит, 'прочитать', чтение),
                            (фасад, 'ранний_допуск', живой),
                            (база.коммит.сообщения, 'прочитать_сообщения', обернуть_читателя('команды', база.коммит.сообщения.прочитать_сообщения)),
                            (база.коммит.модели, 'импортировать', обернуть_читателя('модель', база.коммит.модели.импортировать))):
                        контур.enter_context(mock.patch.object(модуль, название, side_effect=функция))
                    начало = time.perf_counter_ns()
                    итог = трасса.runcall(вход.создать)
                    длительность = time.perf_counter_ns() - начало
                шаги.append({'стадия': имя, 'наносекунды': длительность, 'счётчики': счётчики,
                             'вложенные_стадии_наносекунды': стадии, 'читатели': читатели, 'чтения': чтения})
                return итог

            первый = замер('первичное создание')
            файл = Path(ф.параметры['квитанция'])
            первичная = хэш(файл.read_bytes())
            # Контролируемая разметка фикстуры вне таймера; replay её не канонизирует.
            файл.write_text(json.dumps(json.loads(файл.read_bytes()), ensure_ascii=False, indent=3) + '\n\n')
            перед = снимок(ф); второй = замер('точный повтор'); после = снимок(ф)
            assert первый == второй and перед == после
            повтор = шаги[-1]
            assert all(повтор['счётчики'][ключ] == 0 for ключ in
                       ('установки_квитанции', 'создания_намерения', 'коммиты', 'живой_допуск'))
            assert повтор['читатели'] == [] and '_зафиксировать_новую_квитанцию' not in повтор['вложенные_стадии_наносекунды']
            assert шаги[0]['счётчики']['коммиты'] == 1
            пары.append({'раунд': номер, 'условия': условия, 'первичная_квитанция_sha256': первичная,
                         'снимок_перед_повтором': перед, 'снимок_после_повтора': после,
                         'внешние_вызовы': шаги, 'результат': первый})
        finally: ф.doCleanups()
    пути = манифест.загруженные_пути()
    for запись in трасса.getstats():
        if hasattr(запись.code, 'co_filename'):
            путь = Path(запись.code.co_filename).resolve()
            if путь.is_relative_to(КОРЕНЬ) and путь.suffix == '.py': пути.add(путь)
    assert all(путь in до and до[путь] == хэш(путь.read_bytes()) for путь in пути)
    return {'схема': 'fum.профиль-точного-повтора-квитанции.1', 'часы': 'perf_counter_ns',
            'python': platform.python_version(), 'git': subprocess.check_output(['git', '--version'], text=True).strip(),
            'повторов': 3, 'парные_раунды': пары,
            'медианы_наносекунды': {имя: statistics.median(пара['внешние_вызовы'][номер]['наносекунды'] for пара in пары)
                                    for номер, имя in enumerate(('первичное создание', 'точный повтор'))},
            'исходники': {п.relative_to(КОРЕНЬ).as_posix(): до[п] for п in sorted(пути)},
            'хэши_до_и_после_совпали': True,
            'граница': 'Три малые обычные .4-фикстуры; подготовка, снимки и хэширование вне таймеров. '
                       'cProfile и делегирующие spies включены; вложенные интервалы не суммируются. '
                       'Автообзор не отключён и измерен отдельно; его успешность и физические записи кэша неизвестны. '
                       'Счётчик установок относится только к исходной квитанции; намерение учитывается отдельно. '
                       'Байты чтений не равны дисковому I/O. Кэш ОС не очищается. Это не скорость .9, ROOT или всего FUM.'}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path, required=True)
    параметры = разбор.parse_args(); данные = измерить()
    with параметры.выход.open('x', encoding='utf-8') as поток:
        поток.write(json.dumps(данные, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'пар': 3, 'внешних_вызовов': 6, 'исходников': len(данные['исходники']),
                      'медианы_наносекунды': данные['медианы_наносекунды']}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

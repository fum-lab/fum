#!/usr/bin/env python3
"""Парное измерение одинаковых открытых входов и отдельная проверка равенства."""
import argparse
import hashlib
import json
import os
import resource
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_кэш_сверки_остатка as фикстура


def без_профиля(результат):
    return {ключ: значение for ключ, значение in результат.items() if ключ != 'профиль'}


def измерить(проверка, **параметры):
    начало = time.perf_counter_ns()
    результат = проверка.остаток(**параметры)
    время = time.perf_counter_ns() - начало
    чтение = результат['профиль']['чтение_диалога']
    сверки = результат['профиль']['исторические_свидетельства']
    # ru_maxrss: байты на Darwin, KiB на Linux. Это максимум всего процесса,
    # включая подготовку фикстуры, а не приращение отдельного вызова.
    память = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return результат, {'наносекунды': время,
        'максимум_RSS_байты': память if sys.platform == 'darwin' else память * 1024,
        'прочитано_байтов': результат['профиль']['диалог']['прочитано_байтов'],
        'разобрано_строк': результат['профиль']['диалог']['разобрано_строк'],
        'сверки': сверки, 'этапы': результат['профиль'], 'чтение_диалога_наносекунды': чтение}


def профиль(повторов):
    проверка = фикстура.ПроверкаКэша()
    проверка.setUp()
    try:
        # Нейтральные строки увеличивают объём JSONL, не создавая обязательств.
        with проверка.источник.open('ab') as поток:
            for номер in range(1024):
                поток.write(фикстура.фикстура.строка({'type': 'event_msg', 'payload': {'номер': номер, 'текст': 'я' * 4096}}))
        проверка.подготовить(16)
        записи = []
        for сценарий in ('холодный', 'повторный', 'дописанный', 'заменённый'):
            if сценарий == 'холодный':
                проверка.кэш.unlink(missing_ok=True)
                проверка.кэш.with_name(проверка.кэш.name + '.границы').unlink(missing_ok=True)
            elif сценарий == 'дописанный':
                with проверка.источник.open('ab') as поток:
                    поток.write(фикстура.фикстура.строка({'type': 'event_msg', 'payload': {'текст': 'дописано'}}))
            elif сценарий == 'заменённый':
                замена = проверка.источник.with_suffix('.замена')
                замена.write_bytes(проверка.источник.read_bytes())
                os.replace(замена, проверка.источник)
            байты = проверка.источник.read_bytes()
            вход = {'sha256': hashlib.sha256(байты).hexdigest(), 'байты': len(байты),
                    'HEAD': проверка.гит('rev-parse', 'HEAD').decode().strip()}
            полный, метрика_полного = измерить(проверка, перепроверить=True, без_записи=True)
            измерения = []
            for _ in range(повторов):
                быстрый, метрика = измерить(проверка)
                if без_профиля(полный) != без_профиля(быстрый):
                    raise AssertionError('полный и ускоренный остатки различаются')
                измерения.append(метрика)
            записи.append({'сценарий': сценарий, 'вход': вход, 'равенство': True,
                           'полный': метрика_полного, 'ускоренный': измерения})
        return {'схема': 'fum.профиль-кэша-сверки-остатка.1', 'повторов': повторов,
            'метод': 'Фикстура вне Git; подготовка исключена из времени; кэш ОС не очищается. RSS включает подготовку.',
            'корректность': all(запись['равенство'] for запись in записи), 'запуски': записи}
    finally:
        проверка.doCleanups()


if __name__ == '__main__':
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--повторов', type=int, default=3)
    разбор.add_argument('--выход', type=Path, required=True)
    аргументы = разбор.parse_args()
    if not 1 <= аргументы.повторов <= 20:
        разбор.error('нужно от 1 до 20 повторов')
    путь = аргументы.выход.absolute()
    if any(os.path.lexists(предок / '.git') for предок in путь.parents) or путь.exists() or путь.is_symlink():
        разбор.error('нужен новый приватный файл вне Git')
    результат = профиль(аргументы.повторов)
    with путь.open('x', encoding='utf-8') as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2)
        поток.write('\n')
    print(json.dumps(результат, ensure_ascii=False))

"""Воспроизводимый профиль отдельного процесса на 1000 материалах."""
import hashlib
import json
from pathlib import Path
import platform
import time

from test_ранний_охват import ПроверкаОхвата, ПУТЬ


def измерить():
    фикстура = ПроверкаОхвата()
    фикстура.setUp()
    try:
        каталог = фикстура.корень / 'Производные'
        каталог.mkdir()
        for номер in range(1000):
            (каталог / f'{номер}.json').write_text('{}\n')
        фикстура.записать('[Запрос](запрос.md)\n[Отчёт](отчёт.md)\n[Производные](../../Производные)')
        замеры = []
        for _ in range(3):
            начало = time.monotonic_ns()
            код, результат = фикстура.вызвать()
            замеры.append(time.monotonic_ns() - начало)
            assert код == 0, результат
        print(json.dumps({'схема': 'fum.профиль-раннего-охвата.1', 'файлов': 1002,
                          'python': platform.python_version(), 'наносекунды': замеры,
                          'скрипт_sha256': hashlib.sha256(ПУТЬ.read_bytes()).hexdigest(),
                          'граница': 'Подготовка исключена; CLI, создание приватного файла разрешения и чтение JSON включены. Кэш ОС не очищен.',
                          'граница_вывода': 'Решение об оптимизации принимается по парным результатам. Ускорение полного допуска не измерено.'}, ensure_ascii=False, indent=2))
    finally:
        фикстура.doCleanups()


if __name__ == '__main__':
    измерить()

"""Воспроизводимый профиль чистой функции; JSON выводится только в stdout."""
import gc
import hashlib
import json
from pathlib import Path
import platform
import statistics
import time
import tracemalloc
from xml.parsers import expat

from test_происхождение_сообщений import МОДУЛЬ, ФРАГМЕНТ, сообщение


def сценарии():
    """Восемь точных синтетических входов, по два на каждую категорию."""
    медиа = сообщение(("команда",), ["user.text", "user.image", "user.audio"])
    медиа["content"] += [
        {"type": "input_image", "image_url": "https://example.invalid/image"},
        {"type": "input_audio", "audio_url": "data:audio/wav;base64,НЕ-ДЕКОДИРОВАТЬ"},
    ]
    return [
        {"название": "буквальная разметка человека", "вход": сообщение(виды=["user.text"]), "ожидается": "человек"},
        {"название": "мультимодальный ввод", "вход": медиа, "ожидается": "человек"},
        {"название": "один служебный фрагмент", "вход": сообщение(), "ожидается": "служебный hook"},
        {"название": "два служебных фрагмента", "вход": сообщение((ФРАГМЕНТ,) * 2), "ожидается": "служебный hook"},
        {"название": "рекомендации расширений", "вход": сообщение(виды=["plugins.recommendations"]), "ожидается": "служебный контекст"},
        {"название": "инструкции и среда", "вход": сообщение(("правила", "среда"), ["agents_md.instructions", "environments.environment_context"]), "ожидается": "служебный контекст"},
        {"название": "неаннотированная команда", "вход": сообщение(("остановись",)), "ожидается": "неоднозначный"},
        {"название": "неполная аннотация", "вход": сообщение((ФРАГМЕНТ,) * 2, ["user.text"]), "ожидается": "неоднозначный"},
    ]


def прогнать(случаи, повторов):
    счётчики = dict.fromkeys(("человек", "служебный hook", "служебный контекст", "неоднозначный"), 0)
    for _ in range(повторов):
        for случай in случаи:
            счётчики[МОДУЛЬ.классифицировать_сообщение(случай["вход"])] += 1
    if any(число != 2 * повторов for число in счётчики.values()):
        raise AssertionError("Состав исходов профиля изменился")
    return счётчики


def измерить():
    начало = time.perf_counter_ns()
    случаи = сценарии()
    байты = json.dumps(случаи, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    подготовка = time.perf_counter_ns() - начало
    for случай in случаи:
        if МОДУЛЬ.классифицировать_сообщение(случай["вход"]) != случай["ожидается"]:
            raise AssertionError("Исход отдельного сценария изменился")
    результаты = []
    for повторов in (100, 10000):
        прогнать(случаи, повторов)  # Один отдельный прогрев, не часть замера.
        замеры = []
        for _ in range(5):
            начало = time.perf_counter_ns()
            счётчики = прогнать(случаи, повторов)
            замеры.append(time.perf_counter_ns() - начало)
        результаты.append({
            "метка": "чистая классификация со счётчиками", "родитель": "профиль",
            "повторов_набора": повторов, "вызовов_за_замер": 8 * повторов,
            "исходы_за_замер": счётчики, "длительности_наносекунды": замеры,
            "медиана_наносекунды": statistics.median(замеры), "исход": "успешно",
        })
    tracemalloc.start()
    прогнать(случаи, 100)
    _, пик = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    return {
        "схема": "fum.профиль-происхождения.1",
        "код_sha256": hashlib.sha256(Path(МОДУЛЬ.__file__).read_bytes()).hexdigest(),
        "сценарий_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "вход_sha256": hashlib.sha256(байты).hexdigest(), "входы": случаи,
        "среда": {"python": platform.python_version(), "expat": expat.EXPAT_VERSION, "сборщик_мусора": gc.isenabled()},
        "условия": "Один процесс, без сети; один прогрев и пять замеров каждого размера; время включает цикл и счётчики, не включает импорт и JSON. Общий хост с другими задачами.",
        "критерий_решения": "Рассмотреть оптимизацию при медиане 80000 вызовов выше 2 с, росте времени выше 150 раз для стократного входа либо пике памяти 800 вызовов выше 1 МиБ. Это ориентиры, не жёсткий тест быстродействия.",
        "подготовка": {"метка": "создание точных входов", "родитель": "профиль", "длительность_наносекунды": подготовка, "исход": "успешно"},
        "измерения": результаты,
        "память": {"метка": "отдельный прогон с tracemalloc", "вызовов": 800, "пик_байты": пик, "не_включён_в_тайминги": True},
    }


if __name__ == "__main__":
    print(json.dumps(измерить(), ensure_ascii=False, sort_keys=True, indent=2))

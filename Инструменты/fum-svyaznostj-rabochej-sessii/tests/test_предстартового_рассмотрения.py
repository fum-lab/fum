class ПредстартовоеРассмотрение(unittest.TestCase):
    def подготовить(сам):
        образец = примеры.ОснованиеКоординации()
        образец.setUp()
        сам.addCleanup(образец.doCleanups)
        образец.папка.chmod(0o700)
        образец.раннее = copy.deepcopy(образец.решение)
        образец.выбор_решения = {'коммит': 'a' * 40, 'путь': 'назначение.json', 'sha256': 'b' * 64}
        образец.выбор_постановки = {'коммит': 'a' * 40, 'путь': 'назначение.md', 'sha256': 'c' * 64}
        образец.строки.append(примеры.байты(примеры.сообщение('Продолжай в прежнем объёме.\n', 3)))
        образец.обновить()
        образец.вход['живой_источник'] = str(образец.источник)
        образец.обзор = {
            'схема': 'fum.предстартовое-рассмотрение-root.1',
            'координатор': примеры.КОРЕНЬ,
            'решение': образец.выбор_решения,
            'постановка': образец.выбор_постановки,
            'исторический_контекст': образец.раннее['координация']['контекст'],
            'координация': copy.deepcopy(образец.смысл)}
        образец.файл_обзора = образец.папка / 'обзор.json'
        сам.сохранить(образец)
        return образец

    def сохранить(сам, образец):
        образец.файл_обзора.write_bytes(примеры.байты(образец.обзор))
        образец.файл_обзора.chmod(0o600)
        образец.хэш_обзора = hashlib.sha256(образец.файл_обзора.read_bytes()).hexdigest()

    def проверить(сам, образец, **уточнения):
        аргументы = {'файл': образец.файл_обзора, 'ожидаемый_хэш': образец.хэш_обзора}
        аргументы.update(уточнения)
        return актуальность.проверить(образец.корень, образец.раннее,
            образец.выбор_решения, образец.выбор_постановки, образец.вход, **аргументы)

    def test_пересмотр_сохраняет_историческое_поручение_и_проверяет_новый_контекст(сам):
        образец = сам.подготовить()
        прежнее = copy.deepcopy(образец.раннее)
        результат = сам.проверить(образец)
        сам.assertEqual(образец.раннее, прежнее)
        сам.assertEqual(результат['исторический_контекст'], прежнее['координация']['контекст'])
        сам.assertEqual(результат['контекст'], образец.смысл['контекст'])
        сам.assertEqual(результат['sha256'], образец.хэш_обзора)
        сам.assertEqual([э['текст'] for э in результат['координация']['оригиналы']],
            ['Координируй дочерние чаты.\n', 'Только результаты и препятствия ROOT.\n',
             'Продолжай в прежнем объёме.\n'])


"""Адресное чтение открытой фикстуры: выбранный интервал и невыбранный хвост."""
import json
import time

from test_нативных_оснований_обратного_приёма import НативныеОснования


def измерить():
    результаты = []
    for размер in (0, 65536, 262144):
        опыт = НативныеОснования()
        опыт.setUp()
        try:
            if размер:
                опыт.промежуточные = [("event_msg", {"type": "пример", "text": "x" * размер})]
            опыт.записать()
            исходный_размер = опыт.путь.stat().st_size
            интервалы = []
            байтов = []
            for хвост in (False, True):
                if хвост:
                    with опыт.путь.open("r+b") as файл:
                        файл.truncate(512 * 1024 * 1024)
                начало = time.perf_counter_ns()
                результат = опыт.вызов()
                интервалы.append(time.perf_counter_ns() - начало)
                байтов.append(результат["прочитано_байт"])
                assert результат["ревью_байты"] == опыт.тело
                assert результат["разрешение_записи"] is False
            assert байтов[0] == байтов[1]
            результаты.append({"исходный_файл_байтов": исходный_размер,
                "добавка_в_выбранном_интервале": размер,
                "первичное_чтение_нс": интервалы[0], "повтор_с_большим_хвостом_нс": интервалы[1],
                "прочитано_байтов_с_заключительной_сверкой": байтов[0]})
        finally:
            опыт.doCleanups()
    return {"схема": "fum.профиль-нативных-оснований.1", "измерения": результаты,
        "граница": "Одна пара наблюдений на размер; подготовка вне интервалов. "
        "Сверка выбранных байтов включена. Хвост 512 МиБ разрежённый; файловый кэш не очищается. "
        "Равенство счётчиков подтверждает отсутствие чтения хвоста, а не ускорение полного FUM. "
        "Git, процессы и эффекты не запускаются читателем."}


if __name__ == "__main__":
    print(json.dumps(измерить(), ensure_ascii=False, sort_keys=True))

def один_запуск():
    проверки = НезависимыйОбычныйЖурнал()
    with репозиторий() as фикс:
        база = проверки.основа(фикс)
        до = {п.relative_to(фикс.root).as_posix(): п.read_bytes()
            for п in (фикс.root / 'Журнал').rglob('*.md')}
        времена = {}
        tracemalloc.start()
        def измерить(имя, действие):
            начало = time.perf_counter_ns()
            результат = действие()
            времена[имя] = time.perf_counter_ns() - начало
            return результат
        измерить('чистый_план_P.1', lambda: журнал.каркас.подготовить_собственную_пару(
            фикс.root, ЭТАПЫ[0], ЭТАПЫ[0].split('_MSK_', 1)[1],
            'Создать первый этап', прежний.THREAD_ID, ['Повтор.\n', 'Повтор.\n']))
        план = измерить('чистый_план', lambda: проверки.план(фикс, база))
        измерить('установка_собственной_пары', lambda: проверки.установить(фикс, план))
        фикс.commit()
        голова = фикс.git('rev-parse', 'HEAD').stdout.strip()
        состав = измерить('полный_состав_Git', lambda: журнал.состав_принятого_дерева(фикс.root, голова))
        индекс = измерить('повтор_состава_и_индекс', lambda: журнал.построить_принятый_индекс(фикс.root, состав))
        фикс.write('Индексы/навигация-журнала.md', индекс['байты'])
        измерить('сверка_смешанного_состава', lambda: журнал.проверить_смешанный(фикс.root, состав))
        начало = time.perf_counter_ns()
        исходный = журнал._гит(КОРЕНЬ, 'rev-parse', 'HEAD').decode().strip()
        большой_состав = журнал.состав_принятого_дерева(КОРЕНЬ, исходный)
        большой_индекс = журнал.построить_принятый_индекс(КОРЕНЬ, большой_состав)
        времена['полный_состав_реальной_базы_и_индекс'] = time.perf_counter_ns() - начало
        _, пик = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        assert индекс['записей'] == 3
        assert len(план[0]) == 2
        assert all((фикс.root / п).read_bytes() == б for п, б in до.items())
        return {'наносекунды': времена, 'пик_памяти_байты': пик,
            'принятых': 3, 'созданных_файлов': 2, 'соседи_сохранены': True,
            'база': исходный, 'записей_реальной_базы': большой_индекс['записей'],
            'байтов_индекса_реальной_базы': len(большой_индекс['байты'])}


def источники_контрольной_точки():
    файлы = {Path(__file__).resolve()}
    каталог = КОРЕНЬ / 'Инструменты'
    файлы.update(каталог.rglob('*.py'))
    файлы.update(каталог.rglob('*.шаблон'))
    assert all(not п.is_symlink() and п.resolve().is_relative_to(каталог)
        for п in файлы), 'необычный источник полного профиля'
    return {п.relative_to(КОРЕНЬ).as_posix(): hashlib.sha256(п.read_bytes()).hexdigest()
        for п in sorted(файлы) if '__pycache__' not in п.parts}


def цикл_контрольной_точки(имя, *, наблюдать_чтения=False):
    """Замеры оборачивают настоящие API; результат каждого API не заменяется."""
    sys.path[:0] = [str(КОРЕНЬ / 'Инструменты/fum-svyaznostj-rabochej-sessii/tests'),
        str(КОРЕНЬ / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts')]
    import test_независимой_контрольной_точки as сценарии
    фикс = (сценарии.РеальныйНезависимыйСоздатель() if имя == 'ROOT'
        else сценарии.РеальныйНезависимыйРебёнок())
    времена = []
    измерения_создателя = []
    наблюдатель = None
    def измеренный(стадия, функция):
        def вызвать(*аргументы, **поля):
            начало = time.perf_counter_ns()
            try:
                вызов = (наблюдатель.обернуть('фаза цикла: ' + стадия, функция)
                    if наблюдатель is not None else функция)
                результат = вызов(*аргументы, **поля)
            except BaseException:
                времена.append({'стадия': стадия, 'порядок': len(времена) + 1,
                    'наносекунды': time.perf_counter_ns() - начало, 'состояние': 'отказ'})
                raise
            времена.append({'стадия': стадия, 'порядок': len(времена) + 1,
                'наносекунды': time.perf_counter_ns() - начало, 'состояние': 'успех'})
            return результат
        return вызвать
    начало = time.perf_counter_ns()
    try:
        фикс.setUp()
        подготовка_фикстуры = time.perf_counter_ns() - начало
        р = фикс if имя == 'ROOT' else фикс.р
        штатный_измеритель = р.м.измерить
        def сохранить_измерение(профиль, название, действие, *аргументы, **поля):
            try:
                вызов = (наблюдатель.обернуть('фаза создателя: ' + название, штатный_измеритель)
                    if наблюдатель is not None else штатный_измеритель)
                return вызов(профиль, название, действие, *аргументы, **поля)
            finally:
                измерения_создателя.append(dict(профиль[-1]))
        функция = (фикс.test_корневая_готовность_коммит_и_повтор_сохраняют_выбранное_поколение
            if имя == 'ROOT' else фикс.test_ребёнок_проходит_полный_цикл_с_двумя_независимыми_входами)
        with contextlib.ExitStack() as стек:
            if наблюдать_чтения:
                import наблюдение_полного_доказательства as чтения
                наблюдатель = чтения.Наблюдение()
                стек.enter_context(чтения.наблюдать(сценарии.связность,
                    сценарии.связность.журнал(), р.свежесть, наблюдатель=наблюдатель))
            стек.enter_context(mock.patch.object(р.м, 'измерить', сохранить_измерение))
            for объект, поле, стадия in (
                (р.м, 'подготовить', 'подготовка'), (р, 'наполнить', 'штатное-наполнение'),
                (р.м, 'объявить_готовность', 'READY'), (р.м, 'создать', 'Creator'),
                (р.свежесть, 'update_repository', 'полная-свежесть-W'),
                (р.ф.отчёты, 'выполнить_запуск', 'адресная-проверка-v4'),
                (р.ф.отчёты, 'выполнить_предпросмотр', 'терминальный-предпросмотр'),
                (сценарии.связность, 'полная_свежесть_основы', 'полная-свежесть-H')):
                стек.enter_context(mock.patch.object(объект, поле,
                    измеренный(стадия, getattr(объект, поле))))
            with contextlib.redirect_stdout(io.StringIO()):
                начало = time.perf_counter_ns(); функция()
                полный_цикл = time.perf_counter_ns() - начало
        результат = {'контур': имя, 'подготовка_фикстуры_наносекунды': подготовка_фикстуры,
            'цикл_наносекунды': полный_цикл, 'интервалы': времена,
            'измерения_создателя': измерения_создателя, 'измерения_создателя_вложены': True,
            'принятый_состав': р.выбранный, 'родитель_A': р.п['исходный_коммит'],
            'основание_этапа': р.п['контракт_журнала']['открытая']['основание'],
            'один_коммит': True, 'epoch_и_квитанция_при_повторе_сохранены': True,
            'принятые_файлы_сохранены': True,
            'общий_MD_индекс_ребёнка_сохранён': True if имя != 'ROOT' else None}
        if наблюдатель is not None:
            результат['наблюдение_чтений'] = наблюдатель.срез()
        return результат
    finally:
        фикс.doCleanups()


def один_запуск_контрольной_точки(принятый_коммит=None):
    голова_основы = журнал._гит(КОРЕНЬ, 'rev-parse', 'HEAD').decode().strip()
    assert принятый_коммит is None or принятый_коммит == голова_основы, 'сменился принятый H до worker'
    код = источники_контрольной_точки()
    начало_процессора = time.process_time_ns()
    циклы = [цикл_контрольной_точки(имя) for имя in ('ROOT', 'ребёнок')]
    sys.path.insert(0, str(КОРЕНЬ / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts'))
    import связность_независимого_журнала as связность
    assert голова_основы == журнал._гит(КОРЕНЬ, 'rev-parse', 'HEAD').decode().strip(), 'сменился H во время циклов'
    tracemalloc.start()
    начало = time.perf_counter_ns()
    ошибки, имена, исходные = связность.полная_свежесть_основы(КОРЕНЬ, голова_основы)
    длительность = time.perf_counter_ns() - начало
    _, пик = tracemalloc.get_traced_memory(); tracemalloc.stop()
    if ошибки:
        raise ValueError('Отказ полной свежести принятого H: ' + '; '.join(ошибки))
    assert код == источники_контрольной_точки(), 'код профиля изменился во время исполнения'
    assert голова_основы == журнал._гит(КОРЕНЬ, 'rev-parse', 'HEAD').decode().strip(), 'сменился H во время полного check'
    пик_памяти_процесса = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return {'циклы': циклы, 'код': код, 'процессор_наносекунды': time.process_time_ns() - начало_процессора,
        'пик_RSS_процесса_байты': пик_памяти_процесса if sys.platform == 'darwin' else пик_памяти_процесса * 1024,
        'полная_свежесть_реального_H': {'коммит': голова_основы, 'наносекунды': длительность,
            'MD_файлов': len(имена), 'байтов_MD': sum(map(len, исходные.values())),
            'пик_памяти_Python_байты': пик, 'ошибок': 0}}


def профиль_контрольной_точки(принятый_коммит=None):
    код = источники_контрольной_точки()
    голова_основы = журнал._гит(КОРЕНЬ, 'rev-parse', 'HEAD').decode().strip()
    assert принятый_коммит is None or принятый_коммит == голова_основы, 'чужой явно выбранный H профиля'
    запуски = []
    for _ in range(3):
        процесс = subprocess.run([sys.executable, '-B', str(Path(__file__).resolve()),
            '--контрольная-точка', '--один-запуск', '--принятый-коммит', голова_основы],
            cwd=КОРЕНЬ, capture_output=True, timeout=240)
        if процесс.returncode:
            sys.stderr.buffer.write(процесс.stderr)
            raise RuntimeError('Отказ обычного профиля: ' + str(процесс.returncode))
        запуски.append(json.loads(процесс.stdout))
    assert all(з['код'] == код for з in запуски) and код == источники_контрольной_точки()
    assert all(з['полная_свежесть_реального_H']['коммит'] == голова_основы for з in запуски)
    assert голова_основы == журнал._гит(КОРЕНЬ, 'rev-parse', 'HEAD').decode().strip(), 'сменился H трёх процессов'
    return {'схема': 'fum.профиль-независимой-контрольной-точки.2', 'код': код, 'принятый_коммит': голова_основы,
        'граница': 'Три новых процесса: реальные Git фикстуры ROOT9 и child10, штатное наполнение, v4, '
            'связность, READY, Creator и повтор; отдельно полный канонический check данных принятого H. '
            'Нативное production исполнение, bridge, R1 и состояние узла не измерены.',
        'предусловия': {'новых_процессов': 3, 'модель_кэша': 'обычный кэш ОС; холодный кэш не заявлен',
            'измерения_API_вложены': True, 'память_H': 'tracemalloc', 'память_процесса': 'ru_maxrss'},
        'медиана_циклов_наносекунды': {имя: int(statistics.median(
            next(ц['цикл_наносекунды'] for ц in з['циклы'] if ц['контур'] == имя) for з in запуски))
            for имя in ('ROOT', 'ребёнок')},
        'медиана_полного_H_наносекунды': int(statistics.median(
            з['полная_свежесть_реального_H']['наносекунды'] for з in запуски)), 'запуски': запуски}


def главная():
    разбор = argparse.ArgumentParser()
    разбор.add_argument('--один-запуск', action='store_true')
    разбор.add_argument('--контрольная-точка', action='store_true')
    разбор.add_argument('--принятый-коммит')
    разбор.add_argument('--выход', type=Path)
    разбор.add_argument('--малый-цикл', choices=('ROOT', 'ребёнок'))
    разбор.add_argument('--наблюдать-чтения', action='store_true')
    параметры = разбор.parse_args()
    if параметры.наблюдать_чтения and not параметры.малый_цикл:
        разбор.error('наблюдение чтений пока доступно только явному малому циклу')
    if параметры.малый_цикл and (параметры.контрольная_точка or параметры.один_запуск
            or параметры.принятый_коммит is not None):
        разбор.error('малый цикл не совмещается с полным профилем или реальной базой')
    if параметры.принятый_коммит is not None and not параметры.контрольная_точка:
        разбор.error('явный H доступен только профилю контрольной точки')
    if параметры.малый_цикл:
        результат = {'схема': 'fum.профиль-чтений-малого-цикла.1',
            'граница': 'Один настоящий цикл на малой Git-фикстуре. Production ROOT и ускорение не измерены.',
            'цикл': цикл_контрольной_точки(параметры.малый_цикл,
                наблюдать_чтения=параметры.наблюдать_чтения)}
    elif параметры.контрольная_точка:
        результат = (один_запуск_контрольной_точки(параметры.принятый_коммит) if параметры.один_запуск
            else профиль_контрольной_точки(параметры.принятый_коммит))
    elif параметры.один_запуск:
        результат = один_запуск()
    else:
        запуски = []
        for _ in range(3):
            процесс = subprocess.run([sys.executable, '-B', str(Path(__file__).resolve()), '--один-запуск'],
                cwd=КОРЕНЬ, capture_output=True, timeout=90)
            if процесс.returncode:
                sys.stderr.buffer.write(процесс.stderr)
                raise RuntimeError('Отказ процесса профиля: ' + str(процесс.returncode))
            запуски.append(json.loads(процесс.stdout))
        источники = [Path(__file__), СТРУКТУРА / 'scripts/независимый_журнал.py',
            СТРУКТУРА / 'tests/test_обычного_независимого_журнала.py',
            КОРЕНЬ / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/независимый_индекс_журнала.py']
        результат = {'схема': 'fum.профиль-обычного-независимого-журнала.1',
            'граница': 'Первый сегмент: две новые карточки, Git-состав и индекс; полный Creator/READY отсутствует.',
            'предусловия': {'новых_процессов': 3, 'записей_основы': 2, 'новых_пар': 1,
                'принятых_записей': 3, 'повреждений': 0},
            'код': {п.relative_to(КОРЕНЬ).as_posix(): hashlib.sha256(п.read_bytes()).hexdigest() for п in источники},
            'медиана_наносекунды': {имя: int(statistics.median(з['наносекунды'][имя] for з in запуски))
                for имя in запуски[0]['наносекунды']}, 'запуски': запуски}
    байты = (json.dumps(результат, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + '\n').encode()
    if параметры.выход:
        with параметры.выход.open('xb') as файл:
            файл.write(байты)
    print(байты.decode(), end='')


if __name__ == '__main__':
    главная()

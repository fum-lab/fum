def ручная_композиция(вход, *, корень):
    """Явная композиция прежних читателей на том же проверяемом перечне, без нового адаптера."""
    канон.поля(вход, {'схема', 'доверие', 'постановка_выбора', 'переходы', 'выбранное', 'позднее_управление'})
    канон.требовать(вход['схема'] == 'fum.цепочка-переходов-задачи-узла.1', 'неизвестная цепочка')
    канон.требовать(type(вход['переходы']) is list and 1 <= len(вход['переходы']) <= 64
        and type(вход['позднее_управление']) is list and len(вход['позднее_управление']) <= 16, 'неверный состав')
    выбор.читатель.загрузить_ожидания(вход['доверие'], корень=корень)
    канон.источник(вход['выбранное'])
    канон.требовать(вход['выбранное'] == вход['переходы'][-1]['источник'], 'не выбран последний переход')
    предыдущий, прежнее, встреченные, покинутые_акты = None, None, set(), set()
    покинутые_этапы = set()
    измерения = {'прочитано_байтов': 0, 'чтений_git_источников': 0}
    for номер, запись in enumerate(вход['переходы'] + вход['позднее_управление']):
        канон.поля(запись, {'источник', 'предыдущий', 'основание'})
        канон.источник(запись['источник'])
        ключ = tuple(запись['источник'][к] for к in ('коммит', 'путь', 'sha256'))
        канон.требовать(ключ not in встреченные and запись['предыдущий'] == предыдущий, 'повтор или неверный порядок')
        встреченные.add(ключ)
        канон.прочитать_источник(корень, запись['основание'], измерения)
        решение = канон.разобрать(канон.прочитать_источник(корень, запись['источник'], измерения))
        канон.решение_координатора(решение)
        канон.требовать(решение['координатор'] == вход['доверие']['координатор']
            and решение['владелец'] == решение['задача'] and решение['задача'] != решение['координатор'], 'чужая задача')
        канон.прочитать_поручение(корень, решение['поручение'], решение['координатор'], решение['задача'])
        текущий_акт = tuple(решение['поручение'][к] for к in ('коммит', 'путь', 'sha256'))
        if прежнее is not None and решение['поручение'] != прежнее['поручение']:
            покинутые_акты.add(tuple(прежнее['поручение'][к] for к in ('коммит', 'путь', 'sha256')))
            покинутые_этапы.add(прежнее['этап'])
        канон.требовать(текущий_акт not in покинутые_акты, 'возврат к покинутому ACT запрещён')
        канон.требовать(решение['этап'] not in покинутые_этапы, 'покинутый этап нельзя переиспользовать')
        if решение['результат'] is not None:
            канон.прочитать_источник(корень, решение['результат']['источник'], измерения)
        if номер >= len(вход['переходы']):
            канон.требовать(решение['состояние'] in ('пауза', 'отменён')
                and решение['поручение'] == прежнее['поручение'], 'чужое позднее управление')
        if прежнее is not None:
            канон.требовать(all(решение[к] == прежнее[к] for к in ('координатор', 'задача', 'владелец', 'хост')), 'чужая идентичность')
            канон.требовать(all(исход != 'unknown' or решение['эффекты'][к] == 'unknown'
                for к, исход in прежнее['эффекты'].items()), 'сброс unknown')
            прежний_акт = решение['поручение'] == прежнее['поручение']
            канон.требовать(прежний_акт == (решение['этап'] == прежнее['этап']), 'смена этапа без нового ACT')
            if прежний_акт:
                канон.требовать(прежнее['состояние'] not in ('закрыт', 'отменён')
                    or решение['состояние'] == прежнее['состояние'], 'повтор закрытого этапа')
                if прежнее['результат'] is not None:
                    канон.требовать(решение['результат'] is not None
                        and решение['результат']['источник'] == прежнее['результат']['источник']
                        and (прежнее['результат']['состояние'] != 'принят'
                            or решение['результат']['состояние'] == 'принят'), 'сброс результата')
        предыдущий, прежнее = запись['источник'], решение
    результат = выбор.построить({'схема': 'fum.выбор-ожиданий-узла.1', 'доверие': вход['доверие'],
        'постановка_выбора': вход['постановка_выбора'], 'решения': [предыдущий]}, корень=корень)
    ожидания = канон.разобрать(результат['кандидат'])
    просмотр = канон.предпросмотр(ожидания['предпросмотр'], корень=корень, каталог_снимков=корень)
    канон.требовать(выбор.читатель.доставка_гит.гит(корень, 'rev-parse', '--verify', вход['доверие']['ref'])
        == вход['доверие']['источник']['коммит'], 'сдвиг поколения')
    return {'кандидат': результат['кандидат'], 'предпросмотр': просмотр}


def измерить(режим, вход, корень):
    источники = {}
    счётчики = {'разборов_JSON': 0, 'логических_байтов_JSON': 0}
    читать = канон.приём_делегации.сверить_источник
    разобрать = json.loads
    def чтение(репо, источник):
        данные = читать(репо, источник)
        ключ = источник['коммит'] + ':' + источник['путь'] + ':' + источник['sha256']
        запись = источники.setdefault(ключ, {'чтений': 0, 'логических_байтов': 0})
        запись['чтений'] += 1; запись['логических_байтов'] += len(данные)
        return данные
    def разбор(данные, *аргументы, **параметры):
        счётчики['разборов_JSON'] += 1
        счётчики['логических_байтов_JSON'] += len(данные.encode('utf-8')) if type(данные) is str else len(данные)
        return разобрать(данные, *аргументы, **параметры)
    with patch.object(канон.приём_делегации, 'сверить_источник', чтение), patch.object(json, 'loads', разбор):
        начало = time.monotonic_ns()
        итог = (ручная_композиция if режим == 'ручной' else гибрид.построить)(вход, корень=корень)
        длительность = time.monotonic_ns() - начало
    смысл = {'кандидат': канон.разобрать(итог['кандидат']), 'предпросмотр': итог['предпросмотр']}
    данные = выбор.читатель.кодировать(смысл)
    return {'режим': режим, 'наносекунды': длительность,
        'RSS_байты_к_моменту_замера': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss * (1 if sys.platform == 'darwin' else 1024),
        'смысл_sha256': hashlib.sha256(данные).hexdigest(), 'кандидат_sha256': hashlib.sha256(итог['кандидат']).hexdigest(),
        'источники': источники, **счётчики, 'физический_IO': 'unknown'}


def исходники():
    корень = Path(__file__).resolve().parents[3]
    пути = {Path(__file__).resolve()}
    for модуль in list(sys.modules.values()):
        имя = getattr(модуль, '__file__', None)
        if имя is not None:
            путь = Path(имя).resolve()
            if путь.is_relative_to(корень) and путь.suffix == '.py':
                пути.add(путь)
    return {str(п.relative_to(корень)): hashlib.sha256(п.read_bytes()).hexdigest() for п in sorted(пути)}


def запустить_работник(команда, *, тайм_аут=120):
    начало = time.monotonic_ns()
    процесс = subprocess.Popen(команда, stdout=subprocess.PIPE, stderr=subprocess.PIPE, start_new_session=True)
    прерван = False
    try:
        вывод, ошибки = процесс.communicate(timeout=тайм_аут)
    except subprocess.TimeoutExpired:
        прерван = True
        try:
            os.killpg(процесс.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        вывод, ошибки = процесс.communicate()
    длительность = time.monotonic_ns() - начало
    return {'код': None if прерван else процесс.returncode, 'тайм_аут': прерван,
        'процесс_наносекунды': длительность,
        'stdout_sha256': hashlib.sha256(вывод).hexdigest(), 'stderr_sha256': hashlib.sha256(ошибки).hexdigest(),
        'stdout_base64': base64.b64encode(вывод).decode('ascii'),
        'stderr_base64': base64.b64encode(ошибки).decode('ascii')}


def сохранить_сырьё(выход, номер, сырьё):
    путь = выход.with_name(выход.stem + '-работник-' + str(номер) + '.json')
    данные = (json.dumps(сырьё, ensure_ascii=False, sort_keys=True, indent=2)+'\n').encode('utf-8')
    with путь.open('xb') as поток:
        поток.write(данные); поток.flush(); os.fsync(поток.fileno())
    дескриптор = os.open(путь.parent, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)
    return {'имя': путь.name, 'sha256': hashlib.sha256(данные).hexdigest()}


def главная():
    разбор = argparse.ArgumentParser(allow_abbrev=False)
    разбор.add_argument('--работник', choices=('ручной', 'гибрид'))
    разбор.add_argument('--корень-фикстуры', type=Path)
    разбор.add_argument('--вход', type=Path)
    разбор.add_argument('--выход', type=Path)
    аргументы = разбор.parse_args()
    if аргументы.работник:
        данные = аргументы.вход.read_bytes(); вход = канон.разобрать(данные)
        до = исходники(); итог = измерить(аргументы.работник, вход, аргументы.корень_фикстуры)
        после = исходники()
        канон.требовать(all(после.get(к) == v for к, v in до.items()), 'изменились исходники работника')
        итог.update(вход_sha256=hashlib.sha256(данные).hexdigest(), исходники=после)
        print(json.dumps(итог, ensure_ascii=False, sort_keys=True))
        return 0
    if аргументы.выход is None:
        разбор.error('нужен --выход')
    канон.требовать(not аргументы.выход.exists(), 'профиль уже существует; повтор записи запрещён')
    канон.требовать(not any(аргументы.выход.with_name(аргументы.выход.stem + '-работник-' + str(номер) + '.json').exists()
        for номер in range(1, 7)), 'сохранено сырьё частичного профиля; повтор работников запрещён')
    аргументы.выход.parent.mkdir(parents=True, exist_ok=True)
    from test_переходов_задачи_узла import ФикстураПереходов
    закреплённые_исходники = исходники()
    with tempfile.TemporaryDirectory(prefix='fum-transition-profile-') as папка:
        начало = time.monotonic_ns(); фикстура = ФикстураПереходов(папка); фикстура.состав()
        подготовка = time.monotonic_ns() - начало
        вход = Path(папка)/'вход.json'; данные = выбор.читатель.кодировать(фикстура.вход)
        вход.write_bytes(данные); вход.chmod(0o600)
        до = фикстура.снимок(); пары = []; сырьё = []; номер_работника = 0
        for номер in range(3):
            пара = []
            for режим in (('ручной', 'гибрид') if номер % 2 == 0 else ('гибрид', 'ручной')):
                команда = [sys.executable, '-B', str(Path(__file__).resolve()), '--работник', режим,
                    '--корень-фикстуры', str(фикстура.с.репо), '--вход', str(вход)]
                номер_работника += 1
                захват = запустить_работник(команда)
                сырьё.append(сохранить_сырьё(аргументы.выход, номер_работника, захват))
                канон.требовать(захват['код'] == 0 and not захват['тайм_аут'],
                    'работник не завершился успешно; полное сырьё сохранено, частичный профиль не принят')
                начало = time.monotonic_ns()
                итог = канон.разобрать(base64.b64decode(захват['stdout_base64'], validate=True))
                итог['разбор_вывода_наносекунды'] = time.monotonic_ns() - начало
                итог['процесс_наносекунды'] = захват['процесс_наносекунды']
                канон.требовать(итог['вход_sha256'] == hashlib.sha256(данные).hexdigest(), 'работник прочитал другой вход')
                канон.требовать(all(закреплённые_исходники.get(к) == v for к, v in итог['исходники'].items()),
                    'работник исполнил незакреплённый исходник')
                итог['stdout_sha256'] = захват['stdout_sha256']
                итог['stderr_sha256'] = захват['stderr_sha256']
                пара.append(итог)
            канон.требовать(пара[0]['смысл_sha256'] == пара[1]['смысл_sha256']
                and пара[0]['кандидат_sha256'] == пара[1]['кандидат_sha256'], 'разный смысл или байты парных результатов')
            пары.append(пара)
        канон.требовать(до == фикстура.снимок() and вход.read_bytes() == данные, 'изменились входы или Git')
        канон.требовать(закреплённые_исходники == исходники(), 'изменился измеряемый код или состав импортов')
        for ключ in ['смысл_sha256', 'кандидат_sha256']:
            канон.требовать(len({работник[ключ] for пара in пары for работник in пара}) == 1,
                'межсерийный дрейф результата')
        результат = {'схема': 'fum.профиль-переходов-задачи-узла.1', 'подготовка_наносекунды': подготовка,
            'вход_sha256': hashlib.sha256(данные).hexdigest(), 'пары': пары, 'исходники': закреплённые_исходники,
            'сырьё_работников': сырьё,
            'Python': sys.version, 'платформа': sys.platform,
            'границы': 'Одна фикстура, три пары независимых процессов без сети. RSS максимум к моменту замера перед финальной сериализацией работника; внутреннее время композиции и внешнее время процесса вложены. SHA фактически прочитанного входа и всех импортированных проектных Python-исходников сверяются, карта включает генератор фикстуры. Это наблюдённый Python closure, стандартная библиотека закреплена версией Python; произвольный непройденный lazy import этим не покрыт. Чтения охватывают успешные Git-источники прежнего сверить_источник, включая ACT; не внутренние чтения Git. JSON охватывает композицию после загрузки входа. Это логические байты, физический I/O и кэш ОС неизвестны. ROOT JSONL не читался.'}
        with аргументы.выход.open('x', encoding='utf-8') as поток:
            поток.write(json.dumps(результат, ensure_ascii=False, sort_keys=True, indent=2)+'\n')
        print(json.dumps({'пары': len(пары), 'вход_sha256': результат['вход_sha256']}, ensure_ascii=False))
        return 0



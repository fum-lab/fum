"""Парный профиль старого допуска и точного выбора на одном открытом корпусе."""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import time

import test_создание_коммита as база


def измерить(параметры):
    начало = time.perf_counter_ns()
    результат = база.коммит.команды(параметры)
    return {'длительность_нс': time.perf_counter_ns() - начало,
        'результат_sha256': hashlib.sha256(база.коммит.байты(результат)).hexdigest()}


def выполнить(выход):
    if выход.exists():
        raise ValueError('Выход уже существует')
    фикстура = база.СозданиеКоммита()
    фикстура.setUp()
    try:
        for номер in range(2048):
            событие = copy.deepcopy(фикстура.события[2])
            событие['payload']['content'][0]['text'] = f'Открытое сообщение {номер}: ' + 'ё' * 2048 + '\n'
            фикстура.события.append(событие)
        фикстура.записать_источник()
        кэш = фикстура.каталог / 'индекс-команд.json'
        снимок = база.прочитать_сообщения(фикстура.источник, база.ЗАДАЧА,
            корень_репозитория=фикстура.корень, кэш=кэш)
        старые = copy.deepcopy(фикстура.параметры)
        старые['источники'][0]['кэш'] = str(кэш)
        новые = copy.deepcopy(старые)
        новые['схема'] = 'fum.создание-коммита.5'
        новые['источники'][0]['граница_снимка'] = {'граница': снимок['граница'],
            'sha256': снимок['sha256'], 'неоднозначные_экземпляры': []}
        исходник_до = фикстура.источник.read_bytes()
        кэш_до = кэш.read_bytes()
        прогрев = {'прежний': измерить(старые), 'выбор': измерить(новые)}
        повторы = []
        for номер in range(3):
            пара = {}
            порядок = [('прежний', старые), ('выбор', новые)]
            if номер % 2: порядок.reverse()
            for имя, параметры in порядок: пара[имя] = измерить(параметры)
            assert пара['прежний']['результат_sha256'] == пара['выбор']['результат_sha256']
            повторы.append(пара)
        assert исходник_до == фикстура.источник.read_bytes() and кэш_до == кэш.read_bytes()
        результат = {'схема': 'fum.профиль-выбранных-команд.1', 'граница':
            'Целый API команды с ранее проверенным приватным кэшем; подготовка корпуса, Git-коммит, модель и Desktop исключены.',
            'вход': {'байты': len(исходник_до), 'sha256': снимок['sha256'], 'сообщений': len(снимок['сообщения'])},
            'код': {п.name: hashlib.sha256(п.read_bytes()).hexdigest() for п in (
                Path(база.коммит.__file__), Path(база.коммит.выбор_команд.__file__), Path(__file__))},
            'прогрев': прогрев, 'повторы': повторы,
            'решение': 'Дополнительная линейная сверка остатка сохраняется как защита; постоянный отдельный индекс неоднозначностей пока не оправдан. Ускорение полного цикла не заявляется.'}
        with os.fdopen(os.open(выход, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), 'w') as поток:
            json.dump(результат, поток, ensure_ascii=False, indent=2)
            поток.write('\n')
        print(json.dumps(результат, ensure_ascii=False))
    finally:
        фикстура.doCleanups()


if __name__ == '__main__':
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', required=True, type=Path)
    выполнить(разбор.parse_args().выход)

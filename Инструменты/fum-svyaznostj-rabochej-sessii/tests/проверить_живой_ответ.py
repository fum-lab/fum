"""Адресно сверить приватный результат обёртки с полными сохранёнными байтами."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from компактный_ответ_задачи import представить_ответ
from компактный_остаток import закодировать


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--применение", type=Path, required=True)
    разбор.add_argument("--выход", type=Path, required=True)
    параметры = разбор.parse_args()
    свидетельство = json.loads(параметры.применение.read_bytes())
    итог, результат = свидетельство["итог"], свидетельство["результат"]
    путь = Path(результат["полный_снимок"]["путь"]); данные = путь.read_bytes()
    эталон = представить_ответ(данные, результат["полный_снимок"]["sha256"], результат["задача"]["id"])
    эталон["полный_снимок"]["путь"] = str(путь)
    if эталон != результат or len(закодировать(результат)) > 16000:
        raise ValueError("Результат отличается от полного снимка или превышает бюджет")
    if итог["запросов"] != 1 or итог["записей"] != 1 or not итог["повторы_равны"]:
        raise ValueError("Не совпало свидетельство одного чтения и трёх повторов")
    каталог = Path(__file__).resolve().parents[1]
    публикация = {"схема": "fum.применение-нативного-ответа.1", "снимок_sha256": hashlib.sha256(данные).hexdigest(),
        "снимок_байты": len(данные), "срез_байты": len(закодировать(результат)),
        "нативных_запросов": 1, "записей_снимка": 1, "повторов": 3, "повторы_равны": True,
        "первое_применение_мс": итог["новый_мс"], "повторное_применение_мс": итог["сохранённый_мс"],
        "ответ_есть": результат["ответ"] is not None,
        "завершение_задачи_доказано": результат["завершение_задачи_доказано"],
        "исходники_sha256": {имя: hashlib.sha256((каталог / имя).read_bytes()).hexdigest() for имя in
            ("scripts/адаптер_ответа.cjs", "scripts/компактный_ответ_задачи.py", "scripts/показать-ответ-задачи.py")},
        "граница": "Один живой запрос собственного хода и три обращения к сохранённому снимку. Счётчики и Date.now получены в functions.exec; это единичные наблюдения внешнего вызова, не парный профиль и не измерение токенов. API, сохранение и запуск CLI включены в первое время. Срез маленького пустого хода может быть больше полного входа."}
    параметры.выход.write_bytes(закодировать(публикация))
    print(json.dumps(публикация, ensure_ascii=False))


if __name__ == "__main__":
    выполнить()

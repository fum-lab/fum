"""Ограниченная контрольная точка не выдаёт остаток за обработанный диалог."""
import copy
import json
from pathlib import Path
import unittest
from unittest import mock

import test_создание_коммита as база


class ВыбранныеКоманды(unittest.TestCase):
    def setUp(сам):
        сам.ф = база.СозданиеКоммита()
        сам.ф.setUp()
        сам.addCleanup(сам.ф.doCleanups)
        сам.ф.события.append({"type": "response_item", "payload": {
            "type": "message", "role": "user", "content": [{"type": "input_text", "text": "<hook_prompt>Неизвестный ввод</hook_prompt>"}],
            "internal_chat_message_metadata_passthrough": {"content_item_kinds": ["unknown"]}}})
        сам.ф.записать_источник()
        сам.снимок = база.прочитать_сообщения(сам.ф.источник, база.ЗАДАЧА,
            корень_репозитория=сам.ф.корень, без_записи=True)
        сам.граница = {"граница": сам.снимок["граница"], "sha256": сам.снимок["sha256"],
            "неоднозначные_экземпляры": [э["экземпляр"] for э in сам.снимок["сообщения"] if э["происхождение"] != "человек"]}

    def включить(сам):
        сам.ф.параметры["схема"] = "fum.создание-коммита.5"
        сам.ф.параметры["источники"][0]["граница_снимка"] = copy.deepcopy(сам.граница)

    def test_старый_режим_сохраняет_отказ(сам):
        сам.ф.отказ_без_коммита(lambda: база.коммит.подготовить(сам.ф.параметры))

    def test_выбор_человека_сохраняет_неизвестный_остаток(сам):
        сам.включить()
        до = сам.ф.источник.read_bytes()
        результат = база.коммит.команды(сам.ф.параметры)
        сам.assertEqual([база.КОМАНДА], [э["текст"] for э in результат])
        сам.assertEqual(до, сам.ф.источник.read_bytes())
        сам.assertFalse(сам.снимок["полнота_подтверждена"])

    def test_отсутствующая_или_ложная_граница_отказывает(сам):
        сам.включить()
        источник = сам.ф.параметры["источники"][0]
        варианты = [None, {**сам.граница, "граница": сам.граница["граница"] - 1},
            {**сам.граница, "sha256": "0" * 64}, {**сам.граница, "неоднозначные_экземпляры": []},
            {**сам.граница, "неоднозначные_экземпляры": сам.граница["неоднозначные_экземпляры"] * 2}]
        for вариант in варианты:
            with сам.subTest(граница=вариант):
                if вариант is None: источник.pop("граница_снимка", None)
                else: источник["граница_снимка"] = вариант
                сам.ф.отказ_без_коммита(lambda: база.коммит.подготовить(сам.ф.параметры))

    def test_выбранный_неизвестный_не_становится_командой(сам):
        сам.включить()
        сам.ф.параметры["источники"][0]["экземпляры"] = сам.граница["неоднозначные_экземпляры"]
        сам.ф.отказ_без_коммита(lambda: база.коммит.подготовить(сам.ф.параметры))

    def test_поздний_ввод_и_оборванный_хвост_отказывают(сам):
        сам.включить()
        до = сам.ф.источник.read_bytes()
        for хвост in (b'{', (json.dumps(сам.ф.события[-1]) + '\n').encode()):
            with сам.subTest(хвост=хвост):
                сам.ф.источник.write_bytes(до + хвост)
                сам.ф.отказ_без_коммита(lambda: база.коммит.подготовить(сам.ф.параметры))
        сам.ф.источник.write_bytes(до)

    def test_рост_во_время_чтения_закрывает_допуск(сам):
        сам.включить()
        снимок = {**сам.снимок, "дописано_после_снимка": 1}
        with mock.patch.object(база.коммит.сообщения, "прочитать_сообщения", return_value=снимок):
            сам.ф.отказ_без_коммита(lambda: база.коммит.подготовить(сам.ф.параметры))

    def test_старый_режим_не_принимает_новое_поле(сам):
        сам.ф.параметры["источники"][0]["граница_снимка"] = сам.граница
        сам.ф.отказ_без_коммита(lambda: база.коммит.подготовить(сам.ф.параметры))

    def test_реальный_коммит_и_повтор_сохраняют_границу(сам):
        сам.включить()
        сам.ф.готовить()
        подготовка = json.loads(Path(сам.ф.параметры["подготовка"]).read_bytes())
        сам.assertEqual("fum.подготовленный-коммит.7", подготовка["схема"])
        сам.assertEqual(сам.граница, подготовка["параметры"]["источники"][0]["граница_снимка"])
        итог = сам.ф.создать()
        сам.assertEqual(итог["коммит"], сам.ф.создать()["коммит"])
        сам.assertIn(база.КОМАНДА, сам.ф.гит("cat-file", "commit", итог["коммит"]))
        кэш = Path(сам.ф.параметры["квитанция"] + ".автообзор")
        обзоры = list(кэш.glob("*/обзор.json"))
        сам.assertEqual(1, len(обзоры))
        обзор = json.loads(обзоры[0].read_bytes())
        сам.assertEqual(итог["коммит"], обзор["коммит"])
        сам.assertEqual("unknown", обзор["неизвестно"]["полная_приёмка"])

    def test_новая_подготовка_не_переносит_готовность_на_поздний_контекст(сам):
        сам.включить()
        сам.ф.готовить()
        новая = copy.deepcopy(сам.ф.события[2])
        новая['payload']['content'][0]['text'] = 'Позднее уточнение.\n'
        сам.ф.события.append(новая)
        сам.ф.записать_источник()
        свежий = база.прочитать_сообщения(сам.ф.источник, база.ЗАДАЧА,
            корень_репозитория=сам.ф.корень, без_записи=True)
        сам.ф.параметры['источники'][0]['граница_снимка'].update(
            граница=свежий['граница'], sha256=свежий['sha256'])
        for ключ in ('сообщение', 'подготовка', 'квитанция'):
            сам.ф.параметры[ключ] += '.новое'
        сам.ф.отказ_без_коммита(lambda: база.коммит.подготовить(сам.ф.параметры))

    def test_прежняя_готовность_без_границы_не_переиспользуется(сам):
        неизвестное = сам.ф.события.pop()
        сам.ф.записать_источник()
        сам.ф.готовить()
        сам.ф.события.append(неизвестное)
        сам.ф.записать_источник()
        сам.включить()
        for ключ in ('сообщение', 'подготовка', 'квитанция'):
            сам.ф.параметры[ключ] += '.новое'
        сам.ф.отказ_без_коммита(lambda: база.коммит.подготовить(сам.ф.параметры))


if __name__ == "__main__":
    unittest.main()

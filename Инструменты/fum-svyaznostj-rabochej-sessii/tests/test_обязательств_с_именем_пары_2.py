"""Синтетическая приёмка v4: новый адрес и прежние неизменяемые доказательства."""
import hashlib
import json
from pathlib import Path
import sys
import subprocess
import unittest

import test_обязательства_задачи_v2 as прежние

КОРЕНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРЕНЬ / 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts'))
sys.path.insert(0, str(КОРЕНЬ / 'Инструменты/fum-struktura-papok-zaprosov/tests'))
import test_братиславского_имени_пары as имена_фикстуры
import обязательства_задачи_v2 as обязательства


class ОбязательстваНовойПары(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        имена_фикстуры.БратиславскоеИмяПары.setUpClass()

    def стенд(сам):
        ф = прежние.ОбязательстваЗадачи()
        ф.подготовить(); сам.addCleanup(ф.doCleanups)
        ф.принять(); ф.коммит(); ф.ожидать(0)
        прежний = ф.запрос
        папка = (ф.корень / прежний).parent
        старые = {п: п.read_bytes() for п in папка.rglob('*') if п.is_file()}
        файлы, план = имена_фикстуры.БратиславскоеИмяПары().новая_пара(
            корень=ф.корень, задача=прежние.ИДЕНТИФИКАТОР, писатель=прежние.ИДЕНТИФИКАТОР,
            команды=['Реализуй наблюдение и запись.'], основание={'коммит': ф.база,
                'путь': прежний, 'sha256': hashlib.sha256((ф.корень / прежний).read_bytes()).hexdigest()})
        for файл in файлы:
            ф.записать(файл.path.as_posix(), файл.data.decode())
        ф.запрос = план['файлы'][0]['путь']
        материалы = Path(ф.запрос).parent / план['имя']['каталоги']['материалы']
        ф.путь_плана = (материалы / 'продолжение.json').as_posix()
        ф.реестр['план_этапа'] = ф.путь_плана
        ф.план['работы'][0]['основание']['запрос'] = ф.запрос
        каталог = материалы / план['имя']['каталоги']['запуски-проверок']
        шаблон = next(ф.data.decode() for ф in файлы if ф.path.name == 'отчёт.md')
        return ф, каталог.as_posix(), шаблон, старые

    def test_новая_приёмка_сохраняет_закрытый_legacy(сам):
        ф, каталог, шаблон, старые = сам.стенд()
        ф.принять(номер_запуска=102, каталог=каталог, шаблон_отчёта=шаблон)
        ф.коммит()
        ответ = ф.вызвать('--профиль')
        сам.assertEqual(0, ответ.returncode, ответ.stderr + ответ.stdout)
        сам.assertEqual('завершить', json.loads(ответ.stdout)['обязательства']['решение'])
        print(ответ.stderr)
        сам.assertEqual(старые, {п: п.read_bytes() for п in старые})

    def test_смешанные_метаданные_и_прежний_RAW_не_принимаются(сам):
        for маркер, прежний_RAW in [('1', False), ('3', False), ('2', True)]:
            with сам.subTest(маркер=маркер, прежний_RAW=прежний_RAW):
                ф, каталог, шаблон, _ = сам.стенд()
                запрос = ф.корень / ф.запрос
                запрос.write_text(запрос.read_text().replace('FUM-ОБЫЧНЫЙ-ЖУРНАЛ: 2',
                    'FUM-ОБЫЧНЫЙ-ЖУРНАЛ: ' + маркер))
                ф.принять(номер_запуска=102, каталог=None if прежний_RAW else каталог,
                    шаблон_отчёта=шаблон)
                ф.коммит(); ф.ожидать(2)

    def test_точный_разбор_нового_имени_сохраняет_старое(сам):
        старое = 'Журнал/2026-09-09_10-00-00_MSK_реализовать-наблюдение/запрос.md'
        новое = 'Журнал/2026-10-25_12-00-00_msk_' + имена_фикстуры.БратиславскоеИмяПары.суффикс + '/запрос.md'
        сам.assertEqual(старое, обязательства.имя_запроса(старое))
        сам.assertEqual(новое, обязательства.имя_запроса(новое))
        for неверное in [новое.replace('_msk_', '_mSk_'), новое.replace('_msk_', '_msk_Manual-'),
                новое.replace('_msk_', '_msk_имя-'), новое.replace('2026-10-25', '2026-02-30')]:
            with сам.subTest(имя=неверное), сам.assertRaises(ValueError):
                обязательства.имя_запроса(неверное)

    def test_разбор_имени_работает_в_изолированном_Python(сам):
        имя = 'Журнал/2026-10-25_12-00-00_msk_' + имена_фикстуры.БратиславскоеИмяПары.суффикс + '/запрос.md'
        код = ('import importlib.util,sys;'
            's=importlib.util.spec_from_file_location("guard",sys.argv[1]);'
            'm=importlib.util.module_from_spec(s);s.loader.exec_module(m);'
            'print(m.имя_запроса(sys.argv[2]))')
        ответ = subprocess.run([sys.executable, '-I', '-S', '-B', '-c', код,
            обязательства.__file__, имя], capture_output=True, text=True)
        сам.assertEqual(0, ответ.returncode, ответ.stderr)
        сам.assertEqual(имя, ответ.stdout.strip())


if __name__ == '__main__':
    unittest.main()

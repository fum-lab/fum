    def проверить_закрытые(сам, р, закрытые):
        открытая = р.ф.запрос.parent.relative_to(р.ф.корень).as_posix()
        текущие = {'Журнал'}
        for каталог, дети, файлы in os.walk(р.ф.корень / 'Журнал', followlinks=False):
            for имя in дети + файлы:
                путь = (Path(каталог) / имя).relative_to(р.ф.корень).as_posix()
                if путь != открытая and not путь.startswith(открытая + '/'):
                    текущие.add(путь)
        сам.assertEqual(set(закрытые), текущие)
        for имя, (тип, сырые, режим) in закрытые.items():
            файл = р.ф.корень / имя
            мета = файл.lstat()
            сам.assertEqual(режим, stat.S_IMODE(мета.st_mode), имя)
            if тип == 'файл':
                сам.assertTrue(stat.S_ISREG(мета.st_mode), имя)
                сам.assertEqual(сырые, файл.read_bytes(), имя)
            else:
                сам.assertTrue(stat.S_ISDIR(мета.st_mode), имя)

    def снимок_повтора(сам, р):
        # Файлы fixture W, private outputs/native/cache и namespace READY.
        результат = {}
        for каталог, дети, файлы in os.walk(р.ф.каталог, followlinks=False):
            for имя in дети + файлы:
                путь = Path(каталог) / имя; мета = путь.lstat()
                сам.assertTrue(stat.S_ISREG(мета.st_mode) or stat.S_ISDIR(мета.st_mode))
                результат[путь.relative_to(р.ф.каталог).as_posix()] = (
                    stat.S_IFMT(мета.st_mode), stat.S_IMODE(мета.st_mode),
                    путь.read_bytes() if stat.S_ISREG(мета.st_mode) else None)
        return результат

    def test_реальное_слияние_ROOT9_и_свежий_повтор(сам):
        р, закрытые = сам.новая()
        р.м.подготовить(р.п, выбранный_состав=р.выбранный)

        р.наполнить(подготовка); р.проверить_данные()
        вход = фасад.ВходКонтрольнойТочки.из_значений(р.п['подготовка'], [база.ЗАПУСК])
        вход.готово(600, выбранный_состав=р.выбранный)
        первый = вход.создать(выбранный_состав=р.выбранный)
        сам.assertEqual(р.п['родители'], первый['родители'])
        сам.assertEqual('1', р.ф.гит('rev-list', '--first-parent', '--count',
            р.п['исходный_коммит'] + '..HEAD').strip())
        сам.проверить_закрытые(р, закрытые)
        selector = р.ф.каталог / 'выбранный-состав-слияния.json'
        selector.write_text(json.dumps(р.выбранный, ensure_ascii=False)); selector.chmod(0o600)
        готовность = р.м.готовность.путь_этапа(подготовка['параметры'])
        защищённые = [Path(р.п[к]) for к in ('подготовка', 'сообщение', 'квитанция')]
        защищённые += [готовность, р.ф.корень / '.git/index']
        до = [п.read_bytes() for п in защищённые]
        полный_снимок = сам.снимок_повтора(р)
        процесс = subprocess.run(р.ф.команда_CLI('создать', '--подготовка', р.п['подготовка'],
            '--проверка', база.ЗАПУСК, '--выбранный-состав', str(selector)),
            capture_output=True, timeout=60)
        сам.assertEqual(0, процесс.returncode, процесс.stderr.decode())
        сам.assertEqual(первый, json.loads(процесс.stdout))
        сам.assertEqual(до, [п.read_bytes() for п in защищённые])
        сам.assertEqual(полный_снимок, сам.снимок_повтора(р))
        сам.assertEqual(первый['коммит'], р.ф.гит('rev-parse', 'HEAD').strip())
        сам.assertEqual(р.п['ветка'], р.ф.гит('symbolic-ref', 'HEAD').strip())
        сам.проверить_закрытые(р, закрытые)



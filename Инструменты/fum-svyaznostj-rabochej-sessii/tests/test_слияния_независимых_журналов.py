    def test_конфликт_двух_отдельно_допустимых_источников_отказывает(сам):
        случаи = [
            ('байты', 'общий.raw', b'left', 0o644, 'общий.raw', b'right', 0o644),
            ('режим', 'общий.raw', b'same', 0o644, 'общий.raw', b'same', 0o755),
            ('регистр', 'Case.raw', b'same', 0o644, 'case.raw', b'same', 0o644),
        ]
        for метка, лп, лб, лм, пп, пб, пм in случаи:
            with сам.subTest(метка=метка):
                ф = независимая.прежний.RepositoryFixture()
                try:
                    ф.root = ф.root.resolve()
                    ф.git('config', 'core.filemode', 'true')
                    ф.make_canonical_layout()
                    база_коммит = ф.git('rev-parse', 'HEAD').stdout.strip()
                    папка = next((ф.root / 'Журнал').glob('*/запрос.md')).parent
                    относительная = папка.relative_to(ф.root).as_posix() + '/материалы/'
                    ф.write(относительная + лп, лб, лм); ф.commit()
                    левый = ф.git('rev-parse', 'HEAD').stdout.strip()
                    ф.git('checkout', '-qb', 'codex/правый', база_коммит)
                    ф.write(относительная + пп, пб, пм); ф.commit()
                    правый = ф.git('rev-parse', 'HEAD').stdout.strip()
                    ж = независимая.связность.журнал()
                    for коммит, имя, режим in [(левый, лп, лм), (правый, пп, пм)]:
                        ж.состав_принятого_дерева(ф.root, коммит)
                        запись = ж._дерево_коммита(ф.root, коммит)[относительная + имя]
                        сам.assertEqual(режим, int(запись[0], 8) & 0o777)
                    до = независимая.снимок(ф.root)
                    причина = ('коллизия компонента управляемой области'
                        if метка == 'регистр' else 'конфликт закрытого Журнала')
                    with сам.assertRaisesRegex(ValueError, причина):
                        ж.состав_принятого_слияния(ф.root, [левый, правый])
                    сам.assertEqual(независимая.снимок(ф.root), до)
                finally:
                    ф.close()




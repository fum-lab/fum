"""Раздельное время конечного копирования кода и повторного чтения его копии."""
import json
import time

from test_копии_кода_обратного_приёма import КопияКода


def измерить():
    опыт = КопияКода()
    опыт.setUp()
    try:
        опыт.поместить_ядро()
        объём = sum((опыт.корень / имя).stat().st_size for имя in опыт.пути)
        начало = time.perf_counter_ns()
        результат = опыт.создать()
        создание = time.perf_counter_ns() - начало
        начало = time.perf_counter_ns()
        проверка = опыт.проверить(результат)
        чтение = time.perf_counter_ns() - начало
        assert проверка["коммит"] == опыт.коммит and результат["файлов"] == len(опыт.пути)
        return {"схема": "fum.профиль-копии-кода-обратного-приёма.1", "опытов": 1,
                "файлов": len(опыт.пути), "байтов": объём,
                "создание_нс": создание, "повторная_проверка_нс": чтение,
                "граница": "Локальная Git-фикстура с настоящими исходниками ядра. "
                "Подготовка фикстуры вне интервалов. Создание включает свою проверку; "
                "повторная проверка измерена отдельным последующим вызовом. "
                "Нет сравнения с созданием worktree или замера полной интеграции."}
    finally:
        опыт.doCleanups()


if __name__ == "__main__":
    print(json.dumps(измерить(), ensure_ascii=False, sort_keys=True))

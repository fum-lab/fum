"""Воспроизводимый профиль обычной и двухродительской контрольных точек."""
import argparse
import cProfile
import hashlib
import json
from pathlib import Path
import time

from test_создание_коммита import СозданиеКоммита


def измерить(выход, подробный):
    наблюдения = []
    профиль = cProfile.Profile()
    for имя in ("test_реальный_коммит_и_повтор_возвращают_один_объект", "test_настоящее_слияние_сохраняет_порядок_обоих_родителей"):
        случай = СозданиеКоммита(имя)
        try:
            случай.setUp()
            начало = time.perf_counter_ns()
            профиль.runcall(getattr(случай, имя))
            длительность = time.perf_counter_ns() - начало
            квитанция = json.loads(Path(случай.параметры["квитанция"]).read_bytes())
            assert квитанция["состояние"] == "проверен"
            наблюдения.append({"сценарий": имя, "длительность_наносекунды": длительность,
                "стадии": квитанция["профиль"], "результат": квитанция["состояние"], "процесс": квитанция["процесс"]})
        finally:
            случай.doCleanups()
    if подробный is not None:
        профиль.dump_stats(str(подробный))
    инструмент = Path(__file__).parents[1] / "scripts/создание_коммита.py"
    результат = {"схема": "fum.профиль-создания-коммита.1", "инструмент_sha256": hashlib.sha256(инструмент.read_bytes()).hexdigest(),
        "граница": "Открытые временные Git и первичные JSONL; исходная подготовка фикстуры исключена. Вызовы внутри сценария вложены и не суммируются с ним.", "наблюдения": наблюдения}
    выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--выход", type=Path, required=True)
    разбор.add_argument("--подробный-профиль", type=Path)
    параметры = разбор.parse_args()
    измерить(параметры.выход, параметры.подробный_профиль)

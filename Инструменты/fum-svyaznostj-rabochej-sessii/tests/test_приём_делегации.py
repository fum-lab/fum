"""Выбранное поручение не становится исполненной работой от пустого остатка."""
import contextlib
import copy
import hashlib
import importlib.util
import io
import json
import os
from pathlib import Path
import sys
import unittest
from unittest import mock

import test_обязательства_задачи as фикстуры

КАТАЛОГ = Path(__file__).resolve().parents[1] / "scripts"
ИСПОЛНИТЕЛЬ = "00000000-0000-4000-8000-000000000456"


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode()


class ПриёмДелегации(unittest.TestCase):
    def setUp(сам):
        сам.фикстура = фикстуры.ТестыОбязательств()
        сам.фикстура.setUp()
        сам.addCleanup(сам.фикстура.doCleanups)
        сам.корень = сам.фикстура.корень
        сам.фикстура.основа["работы"] = [сам.фикстура.работа("НОВАЯ-ПРИЁМКА")]
        сам.фикстура.записать(сам.фикстура.путь, фикстуры.машинные_байты(сам.фикстура.основа))
        сам.путь_поручения = "Журнал/2026-09-10_10-00-00_MSK_восстановить-обязательства/материалы/поручение.json"
        сам.поручение = {"схема": "fum.поручение-координатора.1", "координатор": сам.фикстура.задача,
            "исполнитель": ИСПОЛНИТЕЛЬ, "работа": "НОВАЯ-ПРИЁМКА",
            "поручение": {"действие": "Подготовить отдельный результат.", "ограничения": ["Без нативного Stop."]}}
        сам.фикстура.записать(сам.путь_поручения, байты(сам.поручение))
        сам.ревизия = сам.фикстура.коммит()
        сам.assertEqual(сам.фикстура.проверить()["доступные_работы"], ["НОВАЯ-ПРИЁМКА"])
        сам.выбор = {"координатор": сам.фикстура.задача, "исполнитель": ИСПОЛНИТЕЛЬ,
            "коммит": сам.ревизия, "путь": сам.путь_поручения,
            "sha256": hashlib.sha256(байты(сам.поручение)).hexdigest()}
        сам.запрос = "Журнал/2026-09-11_00-00-00_MSK_проверить-мост/запрос.md"
        сам.фикстура.записать(сам.запрос, ("# Источник\n\n## Текст запроса\n\n````text\nСделай.\n````\n\n## Идентификатор сеанса Codex\n\nCodex-Thread-ID: " + ИСПОЛНИТЕЛЬ + "\n").encode())
        сам.определение = {"идентификатор": "РАБОТА-ИСПОЛНИТЕЛЯ", "действие": сам.поручение["поручение"]["действие"],
            "основание": {"запрос": сам.запрос, "цитата": "Сделай."}}
        сам.план = {"схема": "fum.продолжение-задачи.1", "задача": ИСПОЛНИТЕЛЬ, "режим": "разовая", "остановка": None,
            "работы": [{**сам.определение, "идентификатор": "ПРЕЖНЯЯ", "состояние": "завершена", "свидетельство": "Ранее выполнена."}]}
        сам.сохранить_план()
        сам.фикстура.коммит()
        сам.источник = сам.корень.parent / (сам.корень.name + "-диалог.jsonl")
        сам.addCleanup(сам.источник.unlink, missing_ok=True)
        сам.источник.write_bytes(байты({"type": "session_meta", "payload": {"id": ИСПОЛНИТЕЛЬ}}))
        сам.путь_принятия = f"Планирование/задачи/{ИСПОЛНИТЕЛЬ}/принятие-делегации.json"
        сам.принятие = {"схема": "fum.принятие-делегации.1", "выбранное_поручение": сам.выбор,
            "корневая_работа": "НОВАЯ-ПРИЁМКА", "корневое_основание": сам.фикстура.основа["обязательства"][0]["основание"],
            "план": "план.json", "работа": сам.определение}
        описание = importlib.util.spec_from_file_location("проверяемый_допуск_делегации", КАТАЛОГ / "проверить-продолжение-задачи.py")
        сам.допуск = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(сам.допуск)

    def сохранить_план(сам):
        сам.фикстура.записать("план.json", байты(сам.план))

    def мост(сам):
        import приём_делегации
        return приём_делегации

    def вызвать(сам, выбранный=True):
        аргументы = ["guard", "--корень-репозитория", str(сам.корень), "--codex-thread-id", ИСПОЛНИТЕЛЬ,
            "--исходник", str(сам.источник), "--план", "план.json", "--перед-завершением"]
        выход, ошибки = io.StringIO(), io.StringIO()
        with contextlib.ExitStack() as стек:
            стек.enter_context(mock.patch.object(sys, "argv", аргументы))
            стек.enter_context(mock.patch.dict(os.environ, {"FUM_DELEGATION_TRUST": json.dumps(сам.выбор) if выбранный else ""}))
            if (КАТАЛОГ / "приём_делегации.py").exists():
                стек.enter_context(mock.patch.object(сам.мост(), "КОРНЕВОЙ_ЯКОРЬ", сам.фикстура.граница))
            стек.enter_context(contextlib.redirect_stdout(выход))
            стек.enter_context(contextlib.redirect_stderr(ошибки))
            код = сам.допуск.выполнить()
        return код, выход.getvalue(), ошибки.getvalue()

    def test_проверенное_принятие_без_работы_не_получает_ложный_допуск(сам):
        код, выход, ошибки = сам.вызвать(выбранный=False)
        сам.assertEqual(код, 0, ошибки)
        сам.assertEqual(json.loads(выход)["сообщения"]["остаток"], 0)
        сам.фикстура.записать(сам.путь_принятия, байты(сам.принятие))
        код, выход, ошибки = сам.вызвать()
        сам.assertEqual(код, 2, "Непокрытое принятие ошибочно разрешило завершение: " + выход + ошибки)
        сам.assertIn("не покрыто", ошибки)

    def покрыть(сам):
        сам.фикстура.записать(сам.путь_принятия, байты(сам.принятие))
        сам.план["работы"].append({**сам.определение, "состояние": "доступна", "свидетельство": None})
        сам.сохранить_план()

    def test_покрытие_возвращает_точную_работу_и_код_три(сам):
        сам.покрыть()
        код, выход, ошибки = сам.вызвать()
        сам.assertEqual(код, 3, ошибки)
        сам.assertEqual(json.loads(выход)["обязательства"]["следующая_работа"], "РАБОТА-ИСПОЛНИТЕЛЯ")

    def test_запись_не_выбирает_собственный_якорь(сам):
        сам.покрыть()
        код, _, ошибки = сам.вызвать(выбранный=False)
        сам.assertEqual(код, 2, ошибки)
        сам.assertIn("независимо", ошибки)

    def test_подмены_входа_и_связи_отклоняются(сам):
        сам.покрыть()
        исходное = copy.deepcopy(сам.принятие)
        for поле, значение in (("корневая_работа", "ЧУЖАЯ"), ("корневое_основание", {}), ("план", "другой.json"),
                               ("выбранное_поручение", {**сам.выбор, "sha256": "0" * 64}),
                               ("работа", {**сам.определение, "действие": "Другое."})):
            with сам.subTest(поле=поле):
                сам.фикстура.записать(сам.путь_принятия, байты({**исходное, поле: значение}))
                код, _, ошибки = сам.вызвать()
                сам.assertEqual(код, 2, ошибки)

    def test_удаление_в_истории_не_скрывается_восстановлением(сам):
        сам.покрыть()
        сам.фикстура.коммит()
        (сам.корень / сам.путь_принятия).unlink()
        сам.фикстура.коммит()
        сам.фикстура.записать(сам.путь_принятия, байты(сам.принятие))
        код, _, ошибки = сам.вызвать()
        сам.assertEqual(код, 2, ошибки)
        сам.assertIn("истории", ошибки)

    def test_удаление_рабочей_записи_не_разрешает_завершение(сам):
        сам.покрыть()
        сам.фикстура.коммит()
        (сам.корень / сам.путь_принятия).unlink()
        код, _, ошибки = сам.вызвать()
        сам.assertEqual(код, 2, ошибки)

    def test_отдельный_приём_идемпотентен_и_не_меняет_план(сам):
        прежний = (сам.корень / "план.json").read_bytes()
        with mock.patch.object(сам.мост(), "КОРНЕВОЙ_ЯКОРЬ", сам.фикстура.граница):
            for _ in range(2):
                сам.мост().принять(сам.корень, ИСПОЛНИТЕЛЬ, сам.выбор, сам.принятие, сам.допуск.проверить_основание)
            with сам.assertRaises(RuntimeError):
                сам.мост().принять(сам.корень, ИСПОЛНИТЕЛЬ, сам.выбор, {**сам.принятие, "план": "другой.json"}, сам.допуск.проверить_основание)
        сам.assertEqual((сам.корень / "план.json").read_bytes(), прежний)
        сам.assertEqual(сам.вызвать()[0], 2)

    def test_утрата_принятия_до_первого_коммита_закрывает_допуск(сам):
        with mock.patch.object(сам.мост(), "КОРНЕВОЙ_ЯКОРЬ", сам.фикстура.граница):
            сам.мост().принять(сам.корень, ИСПОЛНИТЕЛЬ, сам.выбор, сам.принятие, сам.допуск.проверить_основание)
        (сам.корень / сам.путь_принятия).unlink()
        код, выход, ошибки = сам.вызвать()
        сам.assertEqual(код, 2, выход + ошибки)

    def test_внешний_отпечаток_и_идентификаторы_проверяются(сам):
        сам.покрыть()
        исходный = copy.deepcopy(сам.выбор)
        for поле, значение in (("sha256", "0" * 64), ("координатор", ИСПОЛНИТЕЛЬ),
                               ("исполнитель", сам.фикстура.задача), ("коммит", сам.ревизия[:10])):
            with сам.subTest(поле=поле):
                сам.выбор = {**исходный, поле: значение}
                сам.принятие["выбранное_поручение"] = сам.выбор
                сам.фикстура.записать(сам.путь_принятия, байты(сам.принятие))
                сам.assertEqual(сам.вызвать()[0], 2)

    def test_приём_не_подменяет_собственное_человеческое_основание(сам):
        сам.покрыть()
        сам.принятие["работа"]["основание"] = {"запрос": сам.фикстура.запрос, "цитата": "Сделай."}
        сам.фикстура.записать(сам.путь_принятия, байты(сам.принятие))
        сам.assertEqual(сам.вызвать()[0], 2)

    def test_поздняя_мутация_принятия_закрывает_допуск(сам):
        сам.покрыть()
        import обработка_сообщений
        исходный = обработка_сообщений.получить_остаток

        def изменить(*аргументы, **параметры):
            результат = исходный(*аргументы, **параметры)
            (сам.корень / сам.путь_принятия).unlink()
            return результат

        with mock.patch.object(обработка_сообщений, "получить_остаток", изменить):
            код, _, ошибки = сам.вызвать()
        сам.assertEqual(код, 2, ошибки)
        сам.assertIn("перед решением", ошибки)

    def test_выбранный_коммит_не_обязан_быть_вершиной_или_её_предком(сам):
        сам.покрыть()
        предок = сам.фикстура.гит("rev-parse", сам.ревизия + "^").decode().strip()
        сам.фикстура.гит("reset", "--soft", предок)
        сам.фикстура.коммит()
        код, _, ошибки = сам.вызвать()
        сам.assertEqual(код, 3, ошибки)


if __name__ == "__main__":
    unittest.main()

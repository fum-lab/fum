"""Первая запись production-state настоящим Git и повтор новым процессом."""
import copy
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import unittest
from unittest.mock import patch

import test_обновление_ожиданий_узла as прежний

ВЕТКА = 'refs/heads/fum-lab/fum'


class ВеткаСостоянияУзла(unittest.TestCase):
    def setUp(сам):
        сам.ф = прежний.ОбновлениеОжиданий()
        сам.ф.setUp()
        сам.addCleanup(сам.ф.doCleanups)
        ф = сам.ф
        ф.ф.гит('rm', 'данные.txt')
        ф.ф.гит('commit', '-qm', 'Закрепить отсутствие первого expected')
        ф.база = ф.ф.гит('rev-parse', 'HEAD').strip()
        ф.ф.гит('branch', '-m', 'fum-lab/fum')
        ф.о.параметры.update(схема='fum.создание-коммита.8', ветка=ВЕТКА,
            исходный_коммит=ф.база, родители=[ф.база])
        ф.вход.update(схема='fum.обновление-ожиданий-узла.2', ветка=ВЕТКА,
            доверие=None, первое_создание={'коммит': ф.база, **ф.ид})
        ф.ф.гит('switch', '-q', 'codex/назначение')
        сам.полномочия = {'схема': 'fum.полномочия-ветки-состояния-узла.1', **ф.ид,
            'ветка': ВЕТКА, 'хэш_корня': hashlib.sha256(str(ф.корень).encode()).hexdigest(),
            'начальный_коммит': ф.о.акт['постановка']['коммит'], 'исходный_коммит': ф.база,
            'путь': 'данные.txt', 'цели': sorted(set(ф.о.параметры['разрешённые_цели']) |
                {ф.о.параметры['запрос'], str(Path(ф.о.параметры['запрос']).with_name('отчёт.md')),
                 ф.о.параметры['история_модели']}),
            'контрольная_ветка': 'refs/heads/codex/полномочия-узла'}
        сам.выбор_полномочий = ф.сохранить('Планирование/полномочия-узла.json', сам.полномочия)
        ф.ф.гит('branch', 'codex/полномочия-узла', сам.выбор_полномочий['коммит'])
        ф.о.акт.update(схема='fum.поручение-дочерней-контрольной-точки.2',
            ветка=ВЕТКА, область=сам.полномочия['цели'], полномочия_узла=сам.выбор_полномочий)
        источник = ф.сохранить('Планирование/обычное-поручение.json', ф.о.акт)
        ф.о.выбор = {**источник, 'координатор': ф.ид['координатор'], 'исполнитель': ф.ид['владелец']}
        ф.о.параметры['выбранное_поручение'] = ф.о.выбор
        ф.вход.update(акт=ф.о.выбор, полномочия_узла=сам.выбор_полномочий)
        ф.решение['поручение'] = ф.о.выбор
        ф.источник_решения = ф.сохранить('Планирование/решение.json', ф.решение)
        ф.контроль['коммит'] = ф.источник_решения['коммит']
        ф.ф.гит('branch', '-f', 'codex/control', ф.контроль['коммит'])
        ф.кандидат['основание'] = ф.источник_решения
        ф.кандидат['предпросмотр']['постановка_выбора'] = ф.источник_решения
        ф.вход['кандидат'] = ф.ссылка_приватная('кандидат.json', ф.кандидат)
        ф.вход.update(решение=ф.источник_решения, контроль=ф.контроль)
        ф.назначение.update(схема='fum.назначение-писателя-ожиданий.3', ветка=ВЕТКА,
            хэш_корня=сам.полномочия['хэш_корня'], полномочия_узла=сам.выбор_полномочий,
            акт=ф.о.выбор, решение=ф.источник_решения, контроль=ф.контроль,
            доверие=None, первое_создание=ф.вход['первое_создание'],
            хэш_кандидата=ф.вход['кандидат']['хэш'])
        ф.назначение.pop('корень')
        ф.вход['назначение'] = ф.сохранить('Планирование/назначение.json', ф.назначение)
        ф.ф.гит('switch', '-q', 'fum-lab/fum')
        ф.вход['параметры'] = ф.ссылка_приватная('параметры.json', ф.о.параметры)

    def test_первая_запись_готовность_коммит_повтор_новым_процессом(сам):
        ф = сам.ф
        ф.установка()
        ф.готовность()
        результат = прежний.писатель.зафиксировать(ф.вход, [прежний.обычная.база.ЗАПУСК])
        сам.assertEqual(результат['коммит']['родители'], [ф.база])
        сам.assertEqual(результат['доверие']['ref'], ВЕТКА)
        сам.assertEqual(json.loads(Path(ф.о.параметры['подготовка']).read_bytes())['схема'],
            'fum.подготовленный-коммит.10')
        # Продвижение кодовой ветки не меняет закреплённое состояние узла.
        ф.ф.гит('switch', '-qc', 'fuma', ф.база)
        (ф.корень/'развитие.txt').write_text('Другая принятая работа\n')
        ф.ф.гит('add', 'развитие.txt'); ф.ф.гит('commit', '-qm', 'Продвинуть независимую fuma')
        ф.ф.гит('switch', '-q', 'fum-lab/fum')
        # Старый читающий повтор остаётся доказуемым после смены активных полномочий.
        ф.ф.гит('branch', '-f', 'codex/полномочия-узла', ф.база)
        вход = ф.приватный('повтор-production.json', ф.вход)
        процесс = subprocess.run([sys.executable, '-B', прежний.писатель.__file__, 'повтор',
            '--вход', str(вход)], capture_output=True, timeout=60)
        сам.assertEqual(процесс.returncode, 0, процесс.stderr.decode())
        сам.assertEqual(json.loads(процесс.stdout), результат)
        сам.assertEqual(ф.ф.гит('rev-list', '--count', ф.база+'..HEAD').strip(), '1')
        сам.assertEqual(прежний.писатель.читатель.загрузить_ожидания(
            результат['доверие'], корень=ф.корень)['ожидания'], ф.кандидат)
        квитанция = Path(ф.о.параметры['квитанция'])
        байты_квитанции = квитанция.read_bytes(); квитанция.unlink()
        до = ф.ф.гит('status', '--porcelain')
        with patch.object(прежний.писатель.коммит, 'создать') as создатель:
            with сам.assertRaisesRegex(ValueError, 'unknown'):
                прежний.писатель.повтор(ф.вход)
            создатель.assert_not_called()
        сам.assertEqual(до, ф.ф.гит('status', '--porcelain'))
        сам.assertEqual(ф.ф.гит('rev-list', '--count', ф.база+'..HEAD').strip(), '1')
        квитанция.write_bytes(байты_квитанции); квитанция.chmod(0o600)

    def test_старый_вход_не_получает_новый_ref(сам):
        вход = copy.deepcopy(сам.ф.вход)
        вход['схема'] = 'fum.обновление-ожиданий-узла.1'
        вход.pop('полномочия_узла')
        with сам.assertRaisesRegex(ValueError, 'codex ref'): прежний.писатель.план(вход)
        сам.assertEqual(сам.ф.ф.гит('rev-parse', 'HEAD').strip(), сам.ф.база)

    def test_изменение_контрольного_поколения_отказывает_до_эффекта(сам):
        сам.ф.ф.гит('branch', '-f', 'codex/полномочия-узла', сам.ф.база)
        with сам.assertRaisesRegex(ValueError, 'контрольное поколение полномочий'):
            прежний.писатель.план(сам.ф.вход)
        сам.assertFalse((сам.ф.корень/'данные.txt').exists())

    def сохранить_независимый(сам, имя, значение):
        сам.ф.ф.гит('switch', '-q', 'codex/назначение')
        итог = сам.ф.сохранить(имя, значение)
        сам.ф.ф.гит('switch', '-q', 'fum-lab/fum')
        return итог

    def test_копия_полномочий_не_подменяет_независимый_акт(сам):
        ф = сам.ф
        сам.assertFalse(прежний.писатель.план(ф.вход)['допуск_эффекта'])
        подмена = {**сам.полномочия, 'узел': 'другой-узел'}
        источник = сам.сохранить_независимый('Планирование/подмена.json', подмена)
        вход = {**ф.вход, 'полномочия_узла': источник}
        with сам.assertRaisesRegex(ValueError, 'копия полномочий'):
            прежний.писатель.план(вход)
        сам.assertFalse((ф.корень/'данные.txt').exists())

    def test_старая_публикуемая_схема_назначения_не_допускает_state(сам):
        ф = сам.ф
        for версия in (1, 2):
            назначение = copy.deepcopy(ф.назначение)
            назначение['схема'] = 'fum.назначение-писателя-ожиданий.'+str(версия)
            назначение.pop('полномочия_узла')
            if версия == 1:
                назначение.pop('хэш_корня'); назначение['корень'] = str(ф.корень)
            выбор = сам.сохранить_независимый('Планирование/старое-назначение.json', назначение)
            with сам.subTest(версия=версия), сам.assertRaisesRegex(ValueError, 'смешаны старое и state'):
                прежний.писатель.план({**ф.вход, 'назначение': выбор})
            сам.assertFalse((ф.корень/'данные.txt').exists())

    def test_изменение_полномочий_после_плана_не_устанавливает_файл(сам):
        ф = сам.ф
        план = прежний.писатель.план(ф.вход)
        ф.ф.гит('branch', '-f', 'codex/полномочия-узла', ф.база)
        до = ф.ф.гит('status', '--porcelain')
        with сам.assertRaisesRegex(ValueError, 'контрольное поколение полномочий'):
            прежний.писатель.установить(ф.вход, план)
        сам.assertFalse((ф.корень/'данные.txt').exists())
        сам.assertEqual(до, ф.ф.гит('status', '--porcelain'))

    def test_корень_владелец_цели_и_база_проверяются_против_акта(сам):
        ф = сам.ф
        import полномочия_ветки_состояния_узла as допуск
        допуск.проверить_дерево(ф.корень, ф.ид['владелец'], ВЕТКА, сам.выбор_полномочий,
            исходный_коммит=ф.база, цели=ф.о.параметры['разрешённые_цели'])
        for замена in ({'исходный_коммит': ф.о.акт['постановка']['коммит']},
                       {'цели': ['чужая.txt']}):
            with сам.subTest(замена=замена), сам.assertRaises(ValueError):
                допуск.проверить_дерево(ф.корень, ф.ид['владелец'], ВЕТКА,
                    сам.выбор_полномочий, **замена)
        with сам.assertRaisesRegex(ValueError, 'дерево, UUID'):
            допуск.проверить_дерево(ф.корень, ф.ид['координатор'], ВЕТКА, сам.выбор_полномочий)
        with patch.dict(os.environ, CODEX_THREAD_ID=ф.ид['координатор']):
            with сам.assertRaisesRegex(ValueError, 'native UUID среды'):
                прежний.писатель.план(ф.вход)

    def test_акт_не_берёт_полномочия_из_непринятой_истории(сам):
        ф = сам.ф
        ф.ф.гит('switch', '-qc', 'codex/акт-отдельно', ф.база)
        источник = ф.сохранить('Планирование/акт-отдельно.json', ф.о.акт)
        ф.ф.гит('switch', '-q', 'fum-lab/fum')
        выбор = {**источник, 'координатор': ф.ид['координатор'], 'исполнитель': ф.ид['владелец']}
        with сам.assertRaisesRegex(ValueError, 'полномочия не приняты в историю ACT'):
            прежний.писатель.обычное.прочитать_акт(ф.корень, выбор)

    def test_прямой_создатель_проверяет_полномочия_после_намерения(сам):
        ф = сам.ф
        ф.установка()
        ф.готовность()
        коммит = ф.о.коммит
        сохранить = коммит.модели.сохранить_сообщение
        квитанция = Path(ф.о.параметры['квитанция'])
        наблюдения = []

        def сменить_после_намерения(путь, текст):
            сохранить(путь, текст)
            if Path(путь) == квитанция:
                сам.assertEqual(json.loads(текст)['состояние'], 'намерение')
                наблюдения.append('намерение сохранено')
                ф.ф.гит('branch', '-f', 'codex/полномочия-узла', ф.база)

        with patch.object(коммит.модели, 'сохранить_сообщение', сменить_после_намерения):
            with сам.assertRaisesRegex(коммит.ОшибкаКоммита, 'контрольное поколение полномочий'):
                коммит.создать(Path(ф.о.параметры['подготовка']),
                    [прежний.обычная.база.ЗАПУСК], доверенное_поручение=ф.о.выбор)
        сам.assertEqual(наблюдения, ['намерение сохранено'])
        сам.assertEqual(ф.ф.гит('rev-parse', 'HEAD').strip(), ф.база)
        сам.assertEqual(json.loads(квитанция.read_bytes())['состояние'], 'намерение')


if __name__ == '__main__':
    unittest.main()

ДРУГАЯ = "00000000-0000-0000-0000-000000000003"


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True) + "\n").encode()


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


class Сценарий:
    def __init__(сам, папка):
        сам.папка = Path(папка).resolve()
        сам.репо = сам.папка / "канон"
        сам.репо.mkdir()
        гит(сам.репо, "init", "-b", "codex/preview")
        (сам.репо / "постановка.md").write_text("Открытая конечная постановка\n")
        сам.постановка = сам.сохранить("постановка.md", (сам.репо / "постановка.md").read_bytes())
        сам.снимки = сам.папка / "снимки"
        сам.снимки.mkdir()
        сам.решение = {"схема": "fum.сохранённое-решение-root.1", "координатор": КООРДИНАТОР,
            "задача": ДОЧЬ, "хост": "local", "этап": "первый-v1", "событие": "наблюдение-1",
            "поручение": сам.акт(ДОЧЬ), "владелец": ДОЧЬ, "ход": "ход-1",
            "состояние": "открыт", "остаток": False, "ожидание": None,
            "результат": None, "план_доставки": None, "эффекты": {"отправка": "не было", "репозиторий": "не было"}}
        сам.вход = {"схема": "fum.вход-предпросмотра-продолжения.2", "координатор": КООРДИНАТОР,
            "постановка_выбора": сам.постановка, "полнота_перечня": False, "исполнители": []}
        сам.добавить(сам.решение)

    def сохранить(сам, имя, данные):
        (сам.репо / имя).write_bytes(данные)
        гит(сам.репо, "add", имя)
        гит(сам.репо, "commit", "--allow-empty", "-m", "Сохранить открытое свидетельство")
        return {"коммит": гит(сам.репо, "rev-parse", "HEAD"), "путь": имя, "sha256": хэш(данные)}

    def акт(сам, задача, постановка=None):
        акт = {"схема": "fum.поручение-дочерней-контрольной-точки.1", "координатор": КООРДИНАТОР,
            "исполнитель": задача, "ветка": "refs/heads/codex/" + задача,
            "область": ["результат.md"], "постановка": сам.постановка if постановка is None else постановка,
            "хэш_нативного_поручения": "a" * 64}
        return {**сам.сохранить("акт-" + задача + ".json", байты(акт)),
            "координатор": КООРДИНАТОР, "исполнитель": задача}

    def снимок(сам, задача, *, ходы=None, статус="idle", курсор=None):
        if ходы is None:
            ходы = [сам.ход()]
        значение = {"schemaVersion": 1, "thread": {"id": задача, "kind": "codex",
            "hostId": "local", "status": {"type": статус}},
            "page": {"order": "newest_first", "limit": 10, "nextCursor": None, "hasMore": False},
            "turns": ходы}
        данные = байты({"content": [{"type": "text", "text": json.dumps(значение, ensure_ascii=False)}]})
        имя = задача + ".json"
        (сам.снимки / имя).write_bytes(данные)
        return {"путь": имя, "sha256": хэш(данные), "наблюдение": "2026-10-08T12:00:00Z",
            "курсор_запроса": курсор}

    @staticmethod
    def ход(ид="ход-1", статус="completed", время=1, текст="Готово"):
        return {"id": ид, "status": статус, "error": None, "startedAt": 0,
            "completedAt": время, "durationMs": время,
            "items": [{"type": "agentMessage", "id": "ответ-" + ид, "text": текст, "phase": "final"}] if текст else []}

    def добавить(сам, решение):
        задача = решение["задача"]
        источник = сам.сохранить("решение-" + задача + ".json", байты(решение))
        сам.вход["исполнители"].append({"задача": задача, "хост": "local", "владелец": задача,
            "поручение": решение["поручение"], "решение_координатора": источник,
            "снимок": сам.снимок(задача), "доставка": None, "необязательная_инфраструктура": False})

    def изменить(сам, **поля):
        сам.решение.update(поля)
        сам.вход["исполнители"][0]["решение_координатора"] = сам.сохранить("решение-" + ДОЧЬ + ".json", байты(сам.решение))

    def вычислить(сам, профиль=None):
        return восстановление.предпросмотр(сам.вход, корень=сам.репо, каталог_снимков=сам.снимки, профиль=профиль)

    def готовый(сам):
        результат = сам.сохранить("результат.md", b"verified result\n")
        сам.изменить(результат={"состояние": "готов", "источник": результат})

    def независимые_постановки(сам):
        первая = сам.сохранить("первая-постановка.md", байты({"объём": "первый"}))
        вторая = сам.сохранить("вторая-постановка.md", байты({"объём": "второй"}))
        сам.изменить(поручение=сам.акт(ДОЧЬ, первая), ожидание="занят первый писатель")
        сам.вход["исполнители"][0]["поручение"] = сам.решение["поручение"]
        решение = copy.deepcopy(сам.решение)
        решение.update(задача=ДРУГАЯ, владелец=ДРУГАЯ, поручение=сам.акт(ДРУГАЯ, вторая),
            ожидание=None, результат={"состояние": "готов", "источник": сам.сохранить("готовый.md", b"ready\n")})
        сам.добавить(решение)
        return {ДОЧЬ: первая, ДРУГАЯ: вторая}



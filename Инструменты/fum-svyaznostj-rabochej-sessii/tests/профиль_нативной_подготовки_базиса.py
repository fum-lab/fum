"""Открытый профиль настоящего CLI; native-рамки строго синтетические."""
import argparse
import json
from pathlib import Path
import platform
import sys
import tempfile
import time

from test_нативной_подготовки_базиса import Пример, генератор, читатель, КОРЕНЬ

def измерить(повторов):
    исходные = {имя:генератор.хэш((КОРЕНЬ/имя).read_bytes()) for имя in генератор.СОСТАВ}
    файлы_измерителя = (Path(__file__), Path(__file__).with_name('test_нативной_подготовки_базиса.py'))
    измеритель = {str(п.relative_to(КОРЕНЬ)):генератор.хэш(п.read_bytes()) for п in файлы_измерителя}
    записи = []
    for номер in range(повторов):
        with tempfile.TemporaryDirectory(prefix='fum-native-profile-') as каталог:
            # Полные Git/native фикстуры и принятый код готовятся вне замера.
            пример = Пример(Path(каталог))
            начало = time.monotonic_ns()
            ожидание = пример.выполнить()
            внешнее = time.monotonic_ns() - начало
            генератор.требовать(пример.внешний.returncode == 0, 'CLI профиля неуспешен')
            результат = читатель.сверить(ожидание)
            квитанция = генератор.разобрать((пример.слот/'квитанция.json').read_bytes())
            записи.append({'повтор':номер+1,
                'внешний_процесс_с_подготовкой_входа_нс':внешнее,
                'фазы':dict(квитанция['профиль'], **результат['профиль']),
                'каналы':{имя:{ключ:э[ключ] for ключ in ('байты','sha256')}
                    for имя,э in квитанция['каналы'].items()},
                'байты_native':Path(ожидание['источник']['путь']).stat().st_size,
                'интервал_sha256':ожидание['источник']['интервал']['sha256'],
                'JS_sha256':ожидание['JS_sha256'],
                'подготовка_код':квитанция['подготовка_код'],
                'наблюдатель_код':квитанция['наблюдатель_код'],
                'разрешение_эффекта':результат['разрешение_эффекта']})
    генератор.требовать(исходные == {имя:генератор.хэш((КОРЕНЬ/имя).read_bytes())
        for имя in генератор.СОСТАВ}, 'код профиля дрейфовал')
    генератор.требовать(измеритель == {str(п.relative_to(КОРЕНЬ)):генератор.хэш(п.read_bytes())
        for п in файлы_измерителя}, 'измеритель дрейфовал')
    return {'схема':'fum.профиль-нативной-подготовки.1',
        'версия_интерпретатора':platform.python_version(),'платформа':sys.platform,
        'замыкание':исходные,'измеритель':измеритель,'повторы':записи,
        'условия':{'настоящий_подготовительный_subprocess':True,'полный_временный_Git':True,
            'синтетический_native':True,'настоящий_host_pilot':False,
            'создание_фикстур_исключено':True,'callback_модель_сеть_не_измерены':True}}

def главный():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path, required=True)
    разбор.add_argument('--повторов', type=int, default=3)
    а = разбор.parse_args()
    генератор.требовать(1 <= а.повторов <= 5, 'неверное число повторов')
    результат = измерить(а.повторов)
    with а.выход.open('xb') as поток: поток.write(генератор.байты(результат))
    а.выход.chmod(0o400)
    print(генератор.байты(результат).decode(), end='')
    return 0

if __name__ == '__main__':
    raise SystemExit(главный())

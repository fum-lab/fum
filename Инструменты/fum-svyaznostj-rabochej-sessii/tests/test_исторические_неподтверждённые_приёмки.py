"""Необратимая граница старых v3-приёмок не должна закрывать остаток."""

import copy
import importlib.util
import json
import os
import subprocess
import sys
import unittest
from pathlib import Path


КОРЕНЬ = Path(__file__).resolve().parents[3]
СКРИПТЫ = Path(os.environ.get("FUM_CHECKED_CODE_ROOT", КОРЕНЬ)) / "Инструменты/fum-svyaznostj-rabochej-sessii/scripts"
sys.path.insert(0, str(СКРИПТЫ))
ОПИСАНИЕ = importlib.util.spec_from_file_location("проверяемые_обязательства", СКРИПТЫ / "обязательства_задачи.py")
МОДУЛЬ = importlib.util.module_from_spec(ОПИСАНИЕ)
ОПИСАНИЕ.loader.exec_module(МОДУЛЬ)


class ТестыИсторическойГраницы(unittest.TestCase):
    @classmethod
    def setUpClass(класс):
        проверка = subprocess.run(["git", "-C", str(КОРЕНЬ), "cat-file", "-e", "43e714e641ae52b6c1f8797947bec482d0d1639c^{commit}"], capture_output=True)
        if проверка.returncode:
            raise unittest.SkipTest("историческая ветка FUMA недоступна")
        путь = КОРЕНЬ / "Планирование/задачи/01a07d3d-d376-7ad2-aafc-67e4c25a67eb/обязательства.json"
        класс.приёмки = json.loads(путь.read_text())["приёмки_этапов"]

    def test_ровно_шесть_закрытых_v3_записей_остаются_неподтверждёнными(сам):
        итог = МОДУЛЬ.проверить_остаток(КОРЕНЬ, МОДУЛЬ.ГРАНИЦА_ЗАДАЧИ)
        непроверенные = [этап for этап in итог["подтверждённые_этапы"] if этап["состояние_проверки"] == "историческая-связь-не-подтверждена"]
        сам.assertEqual({этап["коммит"] for этап in непроверенные}, {
            "76f71fad3adab90f85ae31cb2f7d75f6ceb12e8d",
            "d461aefa874d56aa2160e70b72bbad700ca73030",
            "cd00166b99f78ab173f522c7da0099f67b870b7a",
            "0d524039a55d179f0a9e7b67e7fb5f076fe37fc2",
            "2be70050e077f8c9028508485ddcfa752c337a48",
            "43e714e641ae52b6c1f8797947bec482d0d1639c",
        })
        сам.assertEqual(len(итог["подтверждённые_этапы"]), 7)
        сам.assertFalse(any(этап["актуальна"] for этап in итог["подтверждённые_этапы"]))
        сам.assertFalse(итог["завершение_задачи_доказано"])

    def test_список_исключений_не_разрешает_подмену_заявки_или_отпечатка(сам):
        from закрытый_отчёт_из_гита import проверить_отчёт_в_коммите

        заявка = сам.приёмки[0]
        доказательство = проверить_отчёт_в_коммите(КОРЕНЬ, заявка["коммит"], заявка["запрос"])
        сам.assertTrue(МОДУЛЬ.историческая_неподтверждённая_связь(заявка, доказательство))
        for поле, подмена in (("коммит", "f" * 40), ("запрос", "чужой/запрос.md"), ("финальный_запуск", "00000000-0000-4000-8000-000000000000")):
            изменённая = {**заявка, поле: подмена}
            with сам.subTest(поле=поле):
                сам.assertFalse(МОДУЛЬ.историческая_неподтверждённая_связь(изменённая, доказательство))
        for путь, подмена in (("sha256_снимка", "f" * 64), ("отпечаток_закрытия", "sha256:" + "f" * 64)):
            изменённое = copy.deepcopy(доказательство)
            изменённое[путь] = подмена
            with сам.subTest(путь=путь):
                сам.assertFalse(МОДУЛЬ.историческая_неподтверждённая_связь(заявка, изменённое))
        изменённое = copy.deepcopy(доказательство)
        изменённое["связь"]["кандидат"] = "sha256:" + "f" * 64
        сам.assertFalse(МОДУЛЬ.историческая_неподтверждённая_связь(заявка, изменённое))
        сам.assertFalse(МОДУЛЬ.историческая_неподтверждённая_связь({**заявка, "коммит": []}, доказательство))

    def test_машинное_свидетельство_совпадает_с_узким_допуском(сам):
        from исторические_неподтверждённые_приёмки import НЕПОДТВЕРЖДЁННЫЕ_V3

        путь = КОРЕНЬ / "Журнал/2026-10-02_06-47-55_MSK_исправить-учёт-исторических-приёмок/материалы/исторические-неподтверждённые-приёмки.json"
        материал = json.loads(путь.read_text(encoding="utf-8"))
        сам.assertEqual(материал["схема"], "fum.исторические-неподтверждённые-приёмки.1")
        сам.assertEqual(материал["задача"], МОДУЛЬ.ГРАНИЦА_ЗАДАЧИ["задача"])
        сам.assertEqual({запись["коммит"]: (запись["sha256_заявки"], запись["sha256_доказательства"]) for запись in материал["записи"]}, НЕПОДТВЕРЖДЁННЫЕ_V3)
        сам.assertEqual(len(материал["записи"]), 6)

описание = importlib.util.spec_from_file_location(
    "фикстура_остатка", Path(__file__).with_name("test_обязательства_задачи.py")
)
фикстура = importlib.util.module_from_spec(описание)
описание.loader.exec_module(фикстура)


class СмешаннаяИсторияОбязательств(unittest.TestCase):
    def setUp(сам):
        сам.стенд = фикстура.ТестыОбязательств()
        сам.addCleanup(сам.стенд.doCleanups)
        сам.стенд.setUp()
        сам.исходник = пустой_диалог(сам, сам.стенд.задача)

    def подготовить_слияние(сам, повреждение=None, оформление=None):
        с = сам.стенд
        база = с.источник
        if оформление is not None:
            исходный = с.текст_запроса
            if оформление == "двойной LF":
                исторический = исходный.replace("\n````\n", "\n\n````\n")
            elif оформление == "пробел":
                исторический = исходный.replace("\n````\n", " \n````\n")
            else:
                исторический = исходный.replace("````text\n", "````text\nПример: ")
            с.записать(с.запрос, исторический.encode())
            база = с.коммит()
        архив = json.loads((с.корень / с.архив).read_bytes())
        архив["исходный_коммит"] = база
        архив["план_этапа"] = "план.json"
        for запись in архив["обязательства"]:
            запись["основание"]["коммит"] = база
        старый = copy.deepcopy(архив)
        старый["обязательства"] = старый["обязательства"][:1]
        с.записать(с.путь, фикстура.машинные_байты(старый))
        с.коммит()
        с.записать(с.путь, фикстура.машинные_байты(архив))
        ведущая = с.коммит()
        if повреждение in {"потеря", "приёмка"}:
            испорченный = copy.deepcopy(архив)
            if повреждение == "потеря":
                испорченный["обязательства"].pop()
            else:
                испорченный["обязательства"][0]["приёмки"] = [{"неизвестная": True}]
            с.записать(с.путь, фикстура.машинные_байты(испорченный))
            с.коммит()
            с.записать(с.путь, фикстура.машинные_байты(архив))
            ведущая = с.коммит()
        с.гит("checkout", "--detach", "-q", база)
        с.записать(с.запрос, с.текст_запроса.encode())
        байты = фикстура.машинные_байты(архив)
        карта = json.loads((с.корень / с.карта).read_bytes())
        карта["исторический_генезис"] = база
        карта["исторический_снимок_реестра"].update(
            коммит=ведущая, sha256=hashlib.sha256(байты).hexdigest(), байтов=len(байты)
        )
        с.записать(с.архив, байты)
        с.записать(с.карта, фикстура.машинные_байты(карта))
        с.источник = с.коммит()
        с.граница.update(коммит=с.источник, sha256_архива=hashlib.sha256(байты).hexdigest())
        с.основа = с.модуль.создать_основу(с.корень, с.граница)
        с.записать(с.путь, фикстура.машинные_байты(с.основа))
        основная = с.коммит()
        дерево = с.гит("rev-parse", основная + "^{tree}").decode().strip()
        слияние = с.гит("commit-tree", дерево, "-p", ведущая, "-p", основная,
                        "-m", "Объединить обе истории обязательств").decode().strip()
        с.гит("checkout", "--detach", "-q", слияние)
        сам.архив = архив
        сам.родители = [ведущая, основная]

    def test_слияние_двух_версий_сохраняет_полный_остаток(сам):
        сам.подготовить_слияние()
        с = сам.стенд
        сам.assertEqual(с.гит("rev-list", "--parents", "-n", "1", "HEAD").decode().split()[1:], сам.родители)
        итог = с.проверить()
        сам.assertEqual(set(итог["остаток_обязательств"]), {"СИСТЕМА", "НАБЛЮДЕНИЕ"})
        сам.assertEqual(итог["состояние"], "требуется-план")
        сам.assertFalse(итог["завершение_задачи_доказано"])

    def test_историческая_ограда_с_двойным_переводом_строки_сохраняет_целую_команду(сам):
        сам.подготовить_слияние(оформление="двойной LF")
        итог = сам.стенд.проверить()
        сам.assertEqual(set(итог["остаток_обязательств"]), {"СИСТЕМА", "НАБЛЮДЕНИЕ"})

    def test_историческая_цитата_не_допускает_лишнего_пробела(сам):
        сам.подготовить_слияние(оформление="пробел")
        with сам.assertRaises(сам.стенд.модуль.ОшибкаОтчёта):
            сам.стенд.проверить()

    def test_историческая_цитата_не_является_подстрокой(сам):
        сам.подготовить_слияние(оформление="подстрока")
        with сам.assertRaises(сам.стенд.модуль.ОшибкаОтчёта):
            сам.стенд.проверить()

    def test_потеря_и_возврат_на_старой_линии_не_скрываются_слиянием(сам):
        сам.подготовить_слияние("потеря")
        with сам.assertRaises(сам.стенд.модуль.ОшибкаОтчёта):
            сам.стенд.проверить()

    def test_неизвестная_историческая_приёмка_требует_отдельной_миграции(сам):
        сам.подготовить_слияние("приёмка")
        with сам.assertRaises(сам.стенд.модуль.ОшибкаОтчёта):
            сам.стенд.проверить()

    def test_возврат_к_старой_версии_запрещён(сам):
        сам.подготовить_слияние()
        сам.стенд.записать(сам.стенд.путь, фикстура.машинные_байты(сам.архив))
        сам.стенд.коммит()

"""Поздний ввод не расширяет готовый этап и не обнуляет ожидание фиксации."""
import copy
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import готовность_этапа as готовность


class ГотовностьЭтапа(unittest.TestCase):
    def setUp(сам):
        сам.снимок = {
            "задача": "00000000-0000-0000-0000-000000000001",
            "ветка": "refs/heads/codex/пример", "исходный_коммит": "a" * 40,
            "запрос": "Журнал/этап/запрос.md", "разрешённые_цели": ["код.py", "Журнал/этап/запрос.md"],
            "экземпляры": ["b" * 64], "отпечаток_содержимого": "c" * 64,
            "проверки": ["00000000-0000-0000-0000-000000000002"],
        }
        сам.начало = 1_790_000_000_000_000_000
        сам.запись = готовность.объявить(сам.снимок, сам.начало, 600)

    def test_позднее_сообщение_получает_следующий_этап(сам):
        исходное = copy.deepcopy(сам.запись)
        итог = готовность.оценить(сам.запись, сам.снимок, ["d" * 64], сам.начало + 1_000_000_000)
        сам.assertEqual("зафиксировать-этап", итог["действие"])
        сам.assertEqual(["d" * 64], итог["следующий_этап"])
        сам.assertFalse(итог["начинать_следующий_этап"])
        сам.assertEqual(исходное, сам.запись)

    def test_порог_и_повтор_не_сбрасывают_возраст(сам):
        до = готовность.оценить(сам.запись, сам.снимок, [], сам.начало + 599_999_999_999)
        сам.assertFalse(до["задержка"])
        повтор = готовность.объявить(сам.снимок, сам.начало + 500_000_000_000, 600, прежняя=сам.запись)
        сам.assertEqual(сам.запись, повтор)
        после = готовность.оценить(повтор, сам.снимок, [], сам.начало + 600_000_000_000)
        сам.assertTrue(после["задержка"])
        сам.assertEqual(600_000_000_000, после["возраст_наносекунды"])

    def test_состав_и_отпечаток_нельзя_расширить_повтором(сам):
        изменения = {
            "разрешённые_цели": ["код.py", "Журнал/этап/запрос.md", "ещё.py"],
            "экземпляры": ["b" * 64, "d" * 64],
            "отпечаток_содержимого": "e" * 64,
            "исходный_коммит": "f" * 40,
            "проверки": ["00000000-0000-0000-0000-000000000003"],
        }
        for ключ, значение in изменения.items():
            with сам.subTest(ключ=ключ):
                другой = {**сам.снимок, ключ: значение}
                with сам.assertRaises(ValueError):
                    готовность.объявить(другой, сам.начало + 1, 600, прежняя=сам.запись)
                итог = готовность.оценить(сам.запись, другой, [], сам.начало + 1)
                сам.assertEqual("повторно-проверить-этап", итог["действие"])
                сам.assertFalse(итог["фиксировать_этап"])

    def test_остановка_старше_приоритета_фиксации(сам):
        итог = готовность.оценить(сам.запись, сам.снимок, ["d" * 64], сам.начало + 700_000_000_000, остановлено=True)
        сам.assertEqual("остановиться", итог["действие"])
        сам.assertFalse(итог["фиксировать_этап"])
        сам.assertEqual(["d" * 64], итог["следующий_этап"])

    def test_откат_часов_не_даёт_ложной_свежести(сам):
        with сам.assertRaises(ValueError):
            готовность.оценить(сам.запись, сам.снимок, [], сам.начало - 1)

    def test_замеченная_задержка_не_исчезает_при_откате_часов(сам):
        поздний = готовность.оценить(сам.запись, сам.снимок, [], сам.начало + 700_000_000_000)
        откат = готовность.оценить(сам.запись, сам.снимок, [], сам.начало + 550_000_000_000,
                                 минимальный_возраст=поздний["возраст_наносекунды"])
        сам.assertTrue(откат["задержка"])
        сам.assertEqual(700_000_000_000, откат["возраст_наносекунды"])

    def test_граница_не_делит_мутабельные_списки_с_входом(сам):
        сам.снимок["экземпляры"].append("d" * 64)
        сам.assertEqual(["b" * 64], сам.запись["снимок"]["экземпляры"])

    def test_неполные_повторные_и_небезопасные_поля_не_принимаются(сам):
        варианты = [
            {**сам.снимок, "проверки": []},
            {**сам.снимок, "экземпляры": ["b" * 64, "b" * 64]},
            {**сам.снимок, "разрешённые_цели": ["../чужое"]},
            {**сам.снимок, "разрешённые_цели": ["/абсолют"]},
            {**сам.снимок, "отпечаток_содержимого": "неизвестно"},
            {**сам.снимок, "лишнее": True},
        ]
        for вариант in варианты:
            with сам.assertRaises(ValueError):
                готовность.объявить(вариант, сам.начало, 600)
        for предел in (0, -1, True, 0.5):
            with сам.assertRaises(ValueError):
                готовность.объявить(сам.снимок, сам.начало, предел)

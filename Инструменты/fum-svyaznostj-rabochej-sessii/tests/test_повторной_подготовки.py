"""Рост JSONL без нового наблюдения не меняет уже проверенную историю."""

import hashlib
import json
from pathlib import Path
import subprocess
import sys
import unittest

import test_создание_коммита as основа


class ПовторнаяПодготовка(unittest.TestCase):
    setUp = основа.СозданиеКоммита.setUp
    гит = основа.СозданиеКоммита.гит
    записать_источник = основа.СозданиеКоммита.записать_источник
    команда_CLI = основа.СозданиеКоммита.команда_CLI

    def подготовить_первый(сам):
        основа.коммит.подготовить(сам.параметры)
        сам.история = сам.корень / сам.параметры['история_модели']
        сам.прежние = сам.история.read_bytes()
        сам.курсор = Path(сам.параметры['кэш_модели']).read_bytes()
        for ключ in ('сообщение', 'подготовка', 'квитанция'):
            сам.параметры[ключ] += '.повтор'

    def повторить(сам):
        return основа.коммит.подготовить(сам.параметры, сохранить_историю=True)

    def test_обычное_событие_проверяется_без_записи_в_историю_и_курсор(сам):
        сам.подготовить_первый()
        сам.события.append({'type': 'event_msg', 'payload': {'type': 'agent_message', 'message': 'Наблюдение инструмента'}})
        сам.записать_источник()
        результат = сам.повторить()
        сам.assertEqual(сам.история.read_bytes(), сам.прежние)
        сам.assertEqual(Path(сам.параметры['кэш_модели']).read_bytes(), сам.курсор)
        подготовка = json.loads(Path(сам.параметры['подготовка']).read_text())
        сам.assertEqual(подготовка['история_sha256'], hashlib.sha256(сам.прежние).hexdigest())
        сам.assertNotEqual(результат['сверка_истории']['история_sha256'], подготовка['история_sha256'])
        сам.assertTrue(результат['сверка_истории']['полнота'])
        сам.assertGreater(результат['сверка_истории']['профиль']['разобрано_строк'], 0)

    def test_новое_наблюдение_той_же_пары_требует_обычной_подготовки(сам):
        сам.подготовить_первый()
        сам.события.append(сам.события[1])
        сам.записать_источник()
        with сам.assertRaises(основа.коммит.ОшибкаКоммита):
            сам.повторить()
        сам.assertEqual(сам.история.read_bytes(), сам.прежние)
        сам.assertFalse(Path(сам.параметры['подготовка']).exists())

    def test_повреждённый_и_неполный_хвост_не_подменяются_прежней_историей(сам):
        сам.подготовить_первый()
        исходное = сам.источник.read_bytes()
        for хвост in (b'{broken}\n', b'{"type":'):
            with сам.subTest(хвост=хвост):
                сам.источник.write_bytes(исходное + хвост)
                with сам.assertRaises(основа.коммит.ОшибкаКоммита):
                    сам.повторить()
                сам.assertEqual(сам.история.read_bytes(), сам.прежние)

    def test_изменённый_префикс_закрывается_отказом(сам):
        сам.подготовить_первый()
        сам.источник.write_text(сам.источник.read_text().replace('ultra', 'high'))
        with сам.assertRaises(основа.коммит.ОшибкаКоммита):
            сам.повторить()
        сам.assertEqual(сам.история.read_bytes(), сам.прежние)

    def test_без_сохранённой_истории_повтор_не_создаёт_её(сам):
        with сам.assertRaises(основа.коммит.ОшибкаКоммита):
            сам.повторить()
        сам.assertFalse((сам.корень / сам.параметры['история_модели']).exists())

    def test_CLI_повтора_сохраняет_старые_приватные_файлы(сам):
        сам.подготовить_первый()
        прежние = {п: п.read_bytes() for п in сам.каталог.iterdir() if п.is_file()}
        вход = сам.каталог / 'вход-повтора.json'
        вход.write_text(json.dumps(сам.параметры, ensure_ascii=False))
        результат = subprocess.run(сам.команда_CLI('подготовить-повтор', '--вход', str(вход)),
            capture_output=True, text=True, timeout=15)
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        сам.assertIn('сверка_истории', json.loads(результат.stdout))
        for п, байты in прежние.items():
            сам.assertEqual(п.read_bytes(), байты)

    def test_отсутствующий_курсор_не_восстанавливается_повтором(сам):
        сам.подготовить_первый()
        Path(сам.параметры['кэш_модели']).unlink()
        with сам.assertRaises(основа.коммит.ОшибкаКоммита):
            сам.повторить()
        сам.assertFalse(Path(сам.параметры['кэш_модели']).exists())
        сам.assertEqual(сам.история.read_bytes(), сам.прежние)

    def test_несогласованный_и_подготовленный_курсор_не_допускает_повтор(сам):
        сам.подготовить_первый()
        for вид in ('подготовлено', 'история'):
            with сам.subTest(вид=вид):
                оболочка = json.loads(сам.курсор)
                if вид == 'подготовлено':
                    оболочка['данные']['подготовлено'] = True
                else:
                    оболочка['данные']['история']['число_наблюдений'] += 1
                Path(сам.параметры['кэш_модели']).write_text(json.dumps(оболочка))
                with сам.assertRaises(основа.коммит.ОшибкаКоммита):
                    сам.повторить()
                сам.assertEqual(сам.история.read_bytes(), сам.прежние)


if __name__ == '__main__':
    unittest.main()

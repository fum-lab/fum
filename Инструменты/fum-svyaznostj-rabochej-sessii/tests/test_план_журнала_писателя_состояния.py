class Фикстура:
    def __init__(сам, каталог):
        сам.с = Сценарий(каталог)
        сам.корень = сам.с.репо
        сам.с.вход['исполнители'][0]['снимок'] = None
        сам.старый = 'Журнал/2026-10-10_00-00-00_MSK_проверить-состояние/запрос.md'
        (сам.корень/сам.старый).parent.mkdir(parents=True)
        сам.первоначальный = сам.с.сохранить(сам.старый,
            ('# Прежний запрос\n\nCodex-Thread-ID: '+КООРДИНАТОР+'\n').encode())
        сам.предыдущий = сам.с.сохранить(сам.старый,
            ('# Закрытый прежний этап\n\nCodex-Thread-ID: '+КООРДИНАТОР+'\n').encode())
        # Builder исполняется из канонического checkout, его байты закреплены в H.
        сам.строитель = 'Инструменты/fum-struktura-papok-zaprosov/'
        for относительный, исходник in [
            ('scripts/request_folder_layout.py', Path(этап.каркас.__file__)),
            ('шаблоны/запрос.md.шаблон', этап.каркас.КАТАЛОГ_ШАБЛОНОВ/'запрос.md.шаблон'),
            ('шаблоны/отчёт.md.шаблон', этап.каркас.КАТАЛОГ_ШАБЛОНОВ/'отчёт.md.шаблон')]:
            путь = сам.корень/(сам.строитель+относительный)
            путь.parent.mkdir(parents=True, exist_ok=True); путь.write_bytes(исходник.read_bytes())
        гит(сам.корень, 'add', 'Инструменты'); гит(сам.корень, 'commit', '-m', 'Закрепить строитель пары')
        сам.ид = dict(узел='узел-1', репозиторий='репозиторий-1', координатор=КООРДИНАТОР,
            владелец=ДОЧЬ, поколение_полномочий='поколение-1')
        ожидаемое = {'схема': 'fum.ожидаемое-состояние-узла.1', **сам.ид,
            'основание': сам.с.постановка, 'предпросмотр': сам.с.вход}
        источник = сам.с.сохранить('expected.json', байты(ожидаемое))
        гит(сам.корень, 'switch', '-c', 'fum-lab/fum')
        сам.доверие = {'схема': 'fum.доверие-ожиданиям-узла.1', **сам.ид,
            'ref': 'refs/heads/fum-lab/fum', 'источник': источник}
        сам.нативный = сам.с.папка/'native.jsonl'
        сам.события = [{'type': 'session_meta', 'payload': {'id': КООРДИНАТОР}}]
        for номер, текст in enumerate(['Продолжай.', 'Проверь состояние.', 'Продолжай.']):
            сам.события.append({'type': 'response_item', 'timestamp': f'2026-10-10T00:00:0{номер}Z',
                'payload': {'type': 'message', 'role': 'user',
                    'content': [{'type': 'input_text', 'text': текст}],
                    'internal_chat_message_metadata_passthrough': {'content_item_kinds': ['user.text']}}})
        сам.записать_источник()
        сам.вход = {'схема': 'fum.вход-плана-журнала-писателя-состояния.1',
            'доверие': сам.доверие, 'хэш_корня': хэш(str(сам.корень).encode()),
            'время': 'prefix=2026-10-11_03-00-00_MSK\nlabel=2026-10-11 03:00:00 MSK\n',
            'метка': 'проверить-новое-состояние', 'первоначальный_запрос': сам.первоначальный,
            'предыдущий_этап': сам.предыдущий, 'источники': [сам.источник]}

    def записать_источник(сам):
        сам.нативный.write_bytes(b''.join(байты(э).replace(b'\n', b'')+b'\n' for э in сам.события))
        сам.нативный.chmod(0o600)
        снимок = этап.коммит.сообщения.прочитать_сообщения(сам.нативный, КООРДИНАТОР,
            корень_репозитория=сам.корень, без_записи=True)
        сам.источник = {'путь': str(сам.нативный), 'задача': КООРДИНАТОР,
            'экземпляры': [э['экземпляр'] for э in снимок['сообщения']],
            'граница_снимка': {'sha256': хэш(сам.нативный.read_bytes()),
                'граница': сам.нативный.stat().st_size, 'неоднозначные_экземпляры': []}}

    def построить(сам, **к): return план.построить(сам.вход, корень=сам.корень, **к)

    def снимок(сам):
        return {str(п.relative_to(сам.с.папка)): хэш(п.read_bytes())
            for п in сам.с.папка.rglob('*') if п.is_file()}


class ПланЖурнала(unittest.TestCase):
    def setUp(сам):
        временный = tempfile.TemporaryDirectory(prefix='fum-state-journal-plan-')
        сам.addCleanup(временный.cleanup); сам.ф = Фикстура(временный.name)

    def test_два_каркаса_повторы_проверенное_время_и_неизменная_история(сам):
        до = сам.ф.снимок(); итог = сам.ф.построить(); повтор = сам.ф.построить()
        сам.assertEqual(итог, повтор); сам.assertEqual(до, сам.ф.снимок())
        сам.assertFalse(итог['разрешение_установки']); сам.assertEqual(итог['sha256'], хэш(итог['байты']))
        п = json.loads(итог['байты']); сам.assertEqual(п['схема'], 'fum.план-журнала-писателя-состояния.1')
        сам.assertEqual([э['текст'] for э in п['команды']], ['Продолжай.', 'Проверь состояние.', 'Продолжай.'])
        сам.assertEqual(п['первоначальный_запрос']['путь'], п['предыдущий_этап']['путь'])
        сам.assertEqual([э['режим'] for э in п['файлы']], [0o644, 0o644])
        сам.assertEqual(len(п['файлы']), 2)
        запрос = п['файлы'][0]['текст']
        сам.assertEqual(запрос.count('отложен до передачи координатору'), 2)
        сам.assertIn('Codex-Thread-ID: '+КООРДИНАТОР, запрос)
        сам.assertNotIn(str(сам.ф.с.папка), итог['байты'].decode())

    def test_неверные_поля_время_метка_идентичность_и_SHA(сам):
        исходный = copy.deepcopy(сам.ф.вход)
        for правка in [{'схема': 'неизвестная'}, {'допуск': True}, {'хэш_корня': '0'*64},
                {'метка': '../нет'}, {'время': 'prefix=2026-10-11_03-00-00_MSK\nlabel=2026-10-12 03:00:00 MSK\n'},
                {'доверие': {**сам.ф.доверие, 'владелец': КООРДИНАТОР}},
                {'первоначальный_запрос': {**сам.ф.первоначальный, 'sha256': '0'*64}},
                {'предыдущий_этап': {**сам.ф.предыдущий, 'коммит': 'deadbeef'}}]:
            сам.ф.вход = {**исходный, **правка}
            with сам.assertRaises(ValueError): сам.ф.построить()

    def test_перестановка_повтор_ID_и_изменение_снимка(сам):
        исходный = copy.deepcopy(сам.ф.вход)
        номера = исходный['источники'][0]['экземпляры']
        for порядок in [номера[::-1], [номера[0], номера[0]]]:
            сам.ф.вход = copy.deepcopy(исходный); сам.ф.вход['источники'][0]['экземпляры'] = порядок
            with сам.assertRaises(ValueError): сам.ф.построить()
        сам.ф.вход = исходный
        сам.ф.нативный.write_bytes(сам.ф.нативный.read_bytes()+b'{}\n')
        with сам.assertRaises(ValueError): сам.ф.построить()

    def test_новая_папка_в_checkout_даже_пустая_или_symlink_запрещена(сам):
        каталог = сам.ф.корень/'Журнал/2026-10-11_03-00-00_MSK_проверить-новое-состояние'
        каталог.mkdir()
        with сам.assertRaises(ValueError): сам.ф.построить()
        (каталог/'запрос.md').write_text('Частичная пара')
        with сам.assertRaises(ValueError): сам.ф.построить()
        (каталог/'запрос.md').unlink(); каталог.rmdir(); каталог.symlink_to(сам.ф.с.папка)
        with сам.assertRaises(ValueError): сам.ф.построить()

    def test_коллизия_регистра_закрывает_план(сам):
        (сам.ф.корень/'Журнал/2026-10-11_03-00-00_MSK_ПРОВЕРИТЬ-НОВОЕ-СОСТОЯНИЕ').mkdir()
        with сам.assertRaises(ValueError): сам.ф.построить()

    def test_новая_папка_в_H_закрывает_план(сам):
        путь = 'Журнал/2026-10-11_03-00-00_MSK_проверить-новое-состояние/данные.txt'
        (сам.ф.корень/путь).parent.mkdir(); (сам.ф.корень/путь).write_text('Уже существует')
        гит(сам.ф.корень, 'add', путь); гит(сам.ф.корень, 'commit', '-m', 'Папка уже в H')
        новый = гит(сам.ф.корень, 'rev-parse', 'HEAD'); сам.ф.доверие['источник']['коммит'] = новый
        (сам.ф.корень/путь).unlink(); (сам.ф.корень/путь).parent.rmdir()
        with сам.assertRaises(ValueError): сам.ф.построить()

    def test_папка_только_в_индексе_закрывает_план_и_stdout_CLI(сам):
        путь = сам.ф.корень/'Журнал/2026-10-11_03-00-00_MSK_ПРОВЕРИТЬ-НОВОЕ-СОСТОЯНИЕ/запрос.md'
        путь.parent.mkdir(); путь.write_text('Пара только в индексе')
        гит(сам.ф.корень, 'add', путь.relative_to(сам.ф.корень).as_posix())
        путь.unlink(); путь.parent.rmdir()
        with сам.assertRaisesRegex(ValueError, 'индекс'): сам.ф.построить()
        вход = сам.ф.с.папка/'вход-индекса.json'; вход.write_bytes(байты(сам.ф.вход)); вход.chmod(0o600)
        сценарий = Path(план.__file__).with_name('построить_план_журнала_писателя_состояния.py')
        до = сам.ф.снимок()
        ответ = subprocess.run([sys.executable, '-B', str(сценарий), '--корень-репозитория',
            str(сам.ф.корень), '--вход', str(вход)], capture_output=True)
        сам.assertEqual(ответ.returncode, 1); сам.assertEqual(ответ.stdout, b'')
        сам.assertEqual(до, сам.ф.снимок())

    def test_чужой_trailer_и_строитель_отклоняются(сам):
        исходный = copy.deepcopy(сам.ф.вход)
        чужой = сам.ф.с.сохранить(сам.ф.старый, b'Codex-Thread-ID: 00000000-0000-0000-0000-000000000001\n')
        сам.ф.доверие['источник']['коммит'] = чужой['коммит']
        сам.ф.вход['предыдущий_этап'] = чужой
        with сам.assertRaisesRegex(ValueError, 'другому ROOT'): сам.ф.построить()
        сам.ф.вход = исходный
        сам.ф.с.сохранить(сам.ф.строитель+'scripts/request_folder_layout.py', b'changed\n')
        сам.ф.вход['доверие']['источник']['коммит'] = гит(сам.ф.корень, 'rev-parse', 'HEAD')
        with сам.assertRaisesRegex(ValueError, 'строитель или шаблон'): сам.ф.построить()

    def test_нечеловеческий_выбранный_ввод_отклоняется(сам):
        сам.ф.события[1]['payload']['internal_chat_message_metadata_passthrough']['content_item_kinds'] = ['tool']
        сам.ф.записать_источник(); сам.ф.вход['источники'] = [сам.ф.источник]
        with сам.assertRaises(ValueError): сам.ф.построить()

    def test_дрейф_реального_ref_после_расчёта_закрывает_план(сам):
        начальный = гит(сам.ф.корень, 'rev-parse', 'HEAD')
        гит(сам.ф.корень, 'commit', '--allow-empty', '-m', 'Поздний объект')
        поздний = гит(сам.ф.корень, 'rev-parse', 'HEAD')
        гит(сам.ф.корень, 'update-ref', 'refs/heads/fum-lab/fum', начальный, поздний)
        оригинал = план._отсутствие; вызовы = []
        def дрейф(*а):
            оригинал(*а); вызовы.append(1)
            if len(вызовы) == 2: гит(сам.ф.корень, 'update-ref', 'refs/heads/fum-lab/fum', поздний, начальный)
        with patch.object(план, '_отсутствие', дрейф):
            with сам.assertRaisesRegex(ValueError, 'изменились H'): сам.ф.построить()

    def test_грязный_сосед_не_переписывается_и_профиль_отделён(сам):
        (сам.ф.корень/сам.ф.старый).write_text('Локальная незакреплённая правка')
        до = сам.ф.снимок(); профиль = {}; итог = сам.ф.построить(профиль=профиль)
        сам.assertEqual(до, сам.ф.снимок()); сам.assertEqual(итог, сам.ф.построить())
        сам.assertGreater(профиль['всего_наносекунды'], 0); сам.assertEqual(профиль['API'], 0)

    def test_два_процесса_и_отсутствие_stdout_при_ошибке(сам):
        вход = сам.ф.с.папка/'вход.json'; вход.write_bytes(байты(сам.ф.вход)); вход.chmod(0o600)
        сценарий = Path(план.__file__).with_name('построить_план_журнала_писателя_состояния.py')
        команда = [sys.executable, '-B', str(сценарий), '--корень-репозитория', str(сам.ф.корень), '--вход', str(вход)]
        до = сам.ф.снимок(); ответы = [subprocess.run(команда, capture_output=True) for _ in range(2)]
        сам.assertEqual([э.returncode for э in ответы], [0, 0]); сам.assertEqual(ответы[0].stdout, ответы[1].stdout)
        сам.assertEqual(до, сам.ф.снимок()); сам.assertEqual(ответы[0].stdout, сам.ф.построить()['байты'])
        вход.write_bytes('{"схема":1,"схема":2}'.encode())
        ответ = subprocess.run(команда, capture_output=True); сам.assertEqual(ответ.returncode, 1)
        сам.assertEqual(ответ.stdout, b'')



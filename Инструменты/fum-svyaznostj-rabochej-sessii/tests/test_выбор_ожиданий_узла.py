"""Настоящие Git-объекты: выбор, позднее закрытие, дрейф и отсутствие записи."""
import copy
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

from test_восстановление_прерванной_задачи import Сценарий, КООРДИНАТОР, ДОЧЬ, ДРУГАЯ, байты, хэш, гит
import выбор_ожиданий_узла as выбор


class ВыборОжиданий(unittest.TestCase):
    def setUp(сам):
        временное = tempfile.TemporaryDirectory(prefix='fum-expected-choice-')
        сам.addCleanup(временное.cleanup)
        сам.с = Сценарий(временное.name)
        сам.с.вход['исполнители'][0]['снимок'] = None
        сам.ид = dict(узел='узел-1', репозиторий='репозиторий-1', координатор=КООРДИНАТОР,
            владелец=ДОЧЬ, поколение_полномочий='поколение-1')
        старый = {'схема': 'fum.ожидаемое-состояние-узла.1', **сам.ид,
            'основание': сам.с.постановка, 'предпросмотр': сам.с.вход}
        источник = сам.с.сохранить('expected.json', байты(старый))
        сам.доверие = {'схема': 'fum.доверие-ожиданиям-узла.1', **сам.ид,
            'ref': 'refs/heads/codex/preview', 'источник': источник}
        гит(сам.с.репо, 'switch', '-c', 'codex/выбор')
        сам.решение = copy.deepcopy(сам.с.решение)
        сам.решение.update(состояние='закрыт', остаток=False, ход=None)
        сам.закрытие = сам.с.сохранить('закрытие.json', байты(сам.решение))
        сам.вход = {'схема': 'fum.выбор-ожиданий-узла.1', 'доверие': сам.доверие,
            'постановка_выбора': сам.с.постановка, 'решения': [сам.закрытие]}

    def построить(сам, **kwargs):
        return выбор.построить(сам.вход, корень=сам.с.репо, **kwargs)

    def снимок(сам):
        return {str(п.relative_to(сам.с.репо)): хэш(п.read_bytes())
            for п in сам.с.репо.rglob('*') if п.is_file()}

    def test_позднее_закрытие_порядок_и_неизменная_идентичность(сам):
        другой = copy.deepcopy(сам.решение)
        другой.update(задача=ДРУГАЯ, владелец=ДРУГАЯ, состояние='пауза',
            поручение=сам.с.акт(ДРУГАЯ), ожидание='Пауза пользователя')
        источник = сам.с.сохранить('пауза.json', байты(другой))
        сам.вход['решения'].insert(0, источник)
        результат = сам.построить()
        ожидаемое = json.loads(результат['кандидат'])
        сам.assertEqual({к: ожидаемое[к] for к in сам.ид}, сам.ид)
        сам.assertEqual([а['задача'] for а in ожидаемое['предпросмотр']['исполнители']], [ДРУГАЯ, ДОЧЬ])
        сам.assertEqual(ожидаемое['предпросмотр']['исполнители'][1]['решение_координатора'], сам.закрытие)
        просмотр = выбор.канон.предпросмотр(ожидаемое['предпросмотр'], корень=сам.с.репо,
            каталог_снимков=сам.с.репо)
        сам.assertEqual([а['этап'] for а in просмотр['исполнители']], ['пауза', 'закрыт'])
        сам.assertFalse(результат['допуск_эффекта'])
        сам.assertFalse(ожидаемое['предпросмотр']['полнота_перечня'])
        for а in ожидаемое['предпросмотр']['исполнители']:
            сам.assertIsNone(а['снимок']); сам.assertIsNone(а['доставка'])
            сам.assertFalse(а['необязательная_инфраструктура'])

    def test_точный_повтор_и_грязный_checkout_не_меняют_Git(сам):
        (сам.с.репо/'закрытие.json').write_text('подмена незакреплённого checkout')
        до = сам.снимок()
        а = сам.построить(); б = сам.построить()
        сам.assertEqual(а, б)
        сам.assertEqual(а['sha256'], хэш(а['кандидат']))
        сам.assertEqual(до, сам.снимок())

    def test_невыбранное_позднее_решение_не_заменяет_источник(сам):
        сам.с.сохранить('закрытие.json', байты({**сам.решение, 'состояние': 'открыт'}))
        результат = сам.построить()
        а = json.loads(результат['кандидат'])['предпросмотр']['исполнители'][0]
        данные = выбор.канон.прочитать_источник(сам.с.репо, а['решение_координатора'],
            {'прочитано_байтов': 0, 'чтений_git_источников': 0})
        сам.assertEqual(json.loads(данные)['состояние'], 'закрыт')

    def test_дубликат_задачи_и_ROOT_отклоняются(сам):
        сам.вход['решения'].append(copy.deepcopy(сам.закрытие))
        with сам.assertRaisesRegex(ValueError, 'повтор'): сам.построить()
        сам.вход['решения'] = [сам.с.сохранить('ROOT.json', байты({**сам.решение,
            'задача': КООРДИНАТОР, 'владелец': КООРДИНАТОР}))]
        with сам.assertRaisesRegex(ValueError, 'ROOT'): сам.построить()

    def test_пустой_неограниченный_или_расширенный_вход_отклоняется(сам):
        исходный = copy.deepcopy(сам.вход)
        for правка in ({'решения': []}, {'решения': [сам.закрытие]*129},
                      {'снимок': None}, {'полнота_перечня': True}, {'схема': 'неизвестная'}):
            сам.вход = {**исходный, **правка}
            with сам.assertRaises(ValueError): сам.построить()

    def test_неверные_SHA_путь_и_координатор_отклоняются(сам):
        исходный = copy.deepcopy(сам.вход)
        for правка in ({'sha256': '0'*64}, {'путь': 'нет.json'}, {'путь': '../закрытие.json'}):
            сам.вход = {**исходный, 'решения': [{**сам.закрытие, **правка}]}
            with сам.assertRaises(ValueError): сам.построить()
        сам.вход = {**исходный, 'решения': [сам.с.сохранить('чужой.json', байты({**сам.решение,
            'координатор': ДРУГАЯ}))]}
        with сам.assertRaises(ValueError): сам.построить()

    def test_прежний_ref_и_дрейф_при_чтении_закрывают_результат(сам):
        оригинал = выбор.читатель.загрузить_ожидания
        def дрейф(*а, **к):
            итог = оригинал(*а, **к)
            гит(сам.с.репо, 'update-ref', сам.доверие['ref'], сам.закрытие['коммит'])
            return итог
        with patch.object(выбор.читатель, 'загрузить_ожидания', дрейф):
            with сам.assertRaisesRegex(ValueError, 'поколение'): сам.построить()
        with сам.assertRaises(ValueError): сам.построить()

    def test_результат_решения_тоже_проверяется(сам):
        испорченное = {**сам.решение, 'результат': {'состояние': 'принят',
            'источник': {**сам.с.постановка, 'sha256': '0'*64}}}
        сам.вход['решения'] = [сам.с.сохранить('плохой-результат.json', байты(испорченное))]
        with сам.assertRaises(ValueError): сам.построить()

    def test_профиль_отделён_от_детерминированных_байтов(сам):
        п = {}; итог = сам.построить(профиль=п)
        сам.assertEqual(итог, сам.построить())
        сам.assertEqual(п['выбрано_задач'], 1)
        сам.assertGreater(п['всего_наносекунды'], 0)
        сам.assertEqual(п['реальных_API'], 0)

    def test_два_процесса_и_закрытый_файловый_ввод(сам):
        файл = сам.с.папка/'вход.json'
        файл.write_bytes(байты(сам.вход)); файл.chmod(0o600)
        сценарий = Path(выбор.__file__).with_name('построить_ожидания_узла.py')
        команда = [sys.executable, '-B', str(сценарий), '--корень-репозитория', str(сам.с.репо),
            '--вход', str(файл)]
        до = сам.снимок()
        ответы = [subprocess.run(команда, capture_output=True, check=True) for _ in range(2)]
        сам.assertEqual(ответы[0].stdout, ответы[1].stdout)
        сам.assertEqual(ответы[0].stdout, сам.построить()['кандидат'])
        сам.assertEqual(до, сам.снимок())
        файл.write_bytes('{"схема":1,"схема":2}'.encode('utf-8'))
        ответ = subprocess.run(команда, capture_output=True)
        сам.assertEqual(ответ.returncode, 1); сам.assertEqual(ответ.stdout, b'')
        ссылка = сам.с.папка/'ссылка.json'; ссылка.symlink_to(файл)
        команда[-1] = str(ссылка)
        сам.assertEqual(subprocess.run(команда, capture_output=True).returncode, 1)

    def test_чужой_владелец_и_ACT_отклоняются(сам):
        оригинал = copy.deepcopy(сам.решение)
        for правка in ({'владелец': ДРУГАЯ},
                      {'поручение': {**оригинал['поручение'], 'исполнитель': ДРУГАЯ}}):
            сам.вход['решения'] = [сам.с.сохранить('чужая-связь.json', байты({**оригинал, **правка}))]
            with сам.assertRaises(ValueError): сам.построить()


if __name__ == '__main__':
    unittest.main()

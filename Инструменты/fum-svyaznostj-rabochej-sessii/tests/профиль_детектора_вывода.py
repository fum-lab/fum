"""Семь пар одинакового представления с ручным и автоматическим выбором."""
import argparse
import hashlib
import json
import statistics
import sys
import time
from pathlib import Path

from test_компактный_остаток import снимок, байты
from компактный_остаток import представить, закодировать
from детектор_вывода import потребить


def выполнить():
    разбор=argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход',type=Path,required=True)
    параметры=разбор.parse_args()
    значение=снимок()
    for сообщение in значение['сообщения']:
        сообщение['сырой_объект']={'нагрузка':'ё'*2000000}
    данные=байты(значение); хэш=hashlib.sha256(данные).hexdigest()
    замеры={'ручной-выбор':[],'детектор':[]}; метки=[]; выходы={}; квитанция=None
    for повтор in range(7):
        for имя in (tuple(замеры) if повтор%2==0 else tuple(reversed(замеры))):
            стадии=[]; старт=time.perf_counter_ns()
            if имя=='ручной-выбор':
                вывод=закодировать(представить(данные,хэш,начало=0,число=1,максимум_байтов=16000))
            else:
                вывод,квитанция=потребить(данные,хэш,16000,3,начало=0,число=1,метки=стадии)
            замеры[имя].append(time.perf_counter_ns()-старт)
            выходы[имя]=вывод
            if стадии:метки.append(стадии)
    assert выходы['ручной-выбор']==выходы['детектор']
    каталог=Path(__file__).resolve().parents[1]
    результат={'схема':'fum.профиль-детектора-вывода.1','Python':sys.version.split()[0],
        'вход':{'sha256':хэш,'байты':len(данные)},'бюджет_байтов':16000,'повторы':7,
        'исходники':{имя:hashlib.sha256((каталог/имя).read_bytes()).hexdigest() for имя in
            ('scripts/детектор_вывода.py','scripts/потребить-остаток.py','scripts/компактный_остаток.py',
             'tests/test_детектор_вывода.py','tests/профиль_детектора_вывода.py')},
        'наносекунды':замеры,'медианы':{к:statistics.median(в) for к,в in замеры.items()},'стадии':метки,
        'выход_байтов':len(выходы['детектор']),'квитанция_байтов':len(закодировать(квитанция)),
        'выход_sha256':hashlib.sha256(выходы['детектор']).hexdigest(),'равенство_выхода':True,
        'критерий':'После оптимизации одинаковые вход/SHA/выход и медиана детектора не хуже исходной + max(5мс,25%); ручной выбор — контроль цены автоматического решения.',
        'граница':'Сохранённый открытый вход, один оригинал из трёх. Подготовка, запись и запуск Python исключены; чтение диска/сеть/runtime/токены не измерены. SHA, разбор и представление включены. Стадии вложены в общий вызов и повторно не суммируются.'}
    параметры.выход.write_text(json.dumps(результат,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({к:результат[к] for к in ('вход','медианы','выход_байтов','квитанция_байтов','равенство_выхода')},ensure_ascii=False))


if __name__=='__main__':
    выполнить()

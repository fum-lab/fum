def строка(объект):
    return (json.dumps(объект, ensure_ascii=False) + "\n").encode()


def команда(текст, номер):
    return {"type": "response_item", "payload": {"type": "message", "role": "user", "id": f"human_{номер}",
        "content": [{"type": "input_text", "text": текст}],
        "internal_chat_message_metadata_passthrough": {"content_item_kinds": ["user.text"]}}}


class ПроверкаСлужебнойОболочки(unittest.TestCase):
    def setUp(проверка):
        временный = tempfile.TemporaryDirectory()
        проверка.addCleanup(временный.cleanup)
        проверка.база = Path(временный.name)
        проверка.корень = проверка.база / "проект"
        проверка.корень.mkdir()
        проверка.источник = проверка.база / "исходник.jsonl"
        проверка.кэш = проверка.база / "кэш.json"
        проверка.заголовок = строка({"type": "session_meta", "payload": {"id": ЗАДАЧА}})
        проверка.источник.write_bytes(проверка.заголовок)

    def добавить(проверка, *объекты):
        with проверка.источник.open("ab") as поток:
            for объект in объекты:
                поток.write(строка(объект))

    def служебное(проверка):
        return {"type": "response_item", "payload": copy.deepcopy(ФИКСТУРА["оболочка"])}

    def прочитать(проверка, **параметры):
        return читатель.прочитать_сообщения(проверка.источник, ЗАДАЧА,
            корень_репозитория=проверка.корень, кэш=проверка.кэш, **параметры)

    def подготовить_гит(проверка):
        for аргументы in [("init", "-q"), ("-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
                "commit", "-q", "--allow-empty", "-m", "Синтетическая основа")]:
            subprocess.run(["git", "-C", str(проверка.корень), *аргументы], check=True, capture_output=True)

    def test_команды_порядок_повторы_поручение_и_границы(проверка):
        первая = команда("additional_tools и create_thread остаются буквальным текстом.\n", 1)
        повтор = команда("additional_tools и create_thread остаются буквальным текстом.\n", 2)
        поручение = copy.deepcopy(ФИКСТУРА["поручение"])
        проверка.добавить(первая, проверка.служебное(), поручение, повтор)
        исходные = проверка.источник.read_bytes()
        снимок = проверка.прочитать()
        проверка.assertEqual([э["сырой_объект"] for э in снимок["сообщения"]], [первая["payload"], повтор["payload"]])
        проверка.assertNotEqual(*(э["экземпляр"] for э in снимок["сообщения"]))
        проверка.assertEqual(снимок["граница"], len(исходные))
        проверка.assertEqual(снимок["sha256"], hashlib.sha256(исходные).hexdigest())
        проверка.assertEqual(проверка.источник.read_bytes(), исходные)
        # Ограничение birth: агентское create_thread не входит в human-индекс.
        # Его отдельный принятый разбор K проверяется частным применением дельты.
        проверка.assertNotIn("tools_fixture", json.loads(проверка.кэш.read_text())["данные"]["транспорт"])
        проверка.assertNotIn("delegation_fixture", json.loads(проверка.кэш.read_text())["данные"]["транспорт"])

    def test_неверные_формы_отказывают_до_индекса(проверка):
        for сценарий in ФИКСТУРА["неверные_формы"]:
            with проверка.subTest(путь=сценарий["путь"], сценарий=сценарий):
                событие = проверка.служебное()
                цель = событие["payload"]
                for ключ in сценарий["путь"][:-1]:
                    цель = цель[ключ]
                ключ = сценарий["путь"][-1]
                if сценарий.get("удалить"):
                    del цель[ключ]
                else:
                    цель[ключ] = copy.deepcopy(сценарий["значение"])
                проверка.источник.write_bytes(проверка.заголовок + строка(событие) + строка(команда("Поздняя команда.", 1)))
                with проверка.assertRaises(читатель.ОшибкаСообщений):
                    проверка.прочитать(без_записи=True)
                проверка.assertFalse(проверка.кэш.exists())

    def test_неизвестная_оболочка_с_ролью_и_неверный_тип(проверка):
        for тип in ["future_tools", None, 1, {}, []]:
            with проверка.subTest(тип=тип):
                событие = проверка.служебное()
                событие["payload"]["type"] = тип
                проверка.источник.write_bytes(проверка.заголовок + строка(событие))
                with проверка.assertRaises(читатель.ОшибкаСообщений):
                    проверка.прочитать(без_записи=True)

    def test_принятый_разбор_create_thread_в_полной_основе(проверка):
        путь = КАТАЛОГ.parent / "scripts" / "запуск_приёма_базиса_узла.py"
        if not путь.is_file():
            проверка.skipTest("В birth нет отдельного принятого разбора; запускается в wholeK с узкой дельтой.")
        спецификация = importlib.util.spec_from_file_location("принятый_разбор_поручения_331", путь)
        модуль = importlib.util.module_from_spec(спецификация)
        спецификация.loader.exec_module(модуль)
        поручение = copy.deepcopy(ФИКСТУРА["поручение"])
        поручение.update(timestamp="2026-10-17T00:00:00Z", ordinal=3)
        поручение["payload"]["internal_chat_message_metadata_passthrough"] = {"turn_id": ЗАДАЧА}
        исходные = строка(поручение)
        результат = модуль.первичная_управляющая_рамка(исходные, ЗАДАЧА,
            "00000000-0000-0000-0000-000000000332", ЗАДАЧА)
        проверка.assertEqual(результат["класс"], "адресное-получение")
        проверка.assertFalse(результат["разрешение_эффекта"])
        проверка.assertEqual(результат["sha256"], hashlib.sha256(исходные).hexdigest())
        проверка.assertEqual(результат["содержимое_sha256"],
            hashlib.sha256("Проверь синтетический результат & сохрани порядок.".encode()).hexdigest())

    def test_незавершённая_строка_не_продвигает_границу(проверка):
        событие = строка(проверка.служебное())
        проверка.источник.write_bytes(проверка.заголовок + событие[:-1])
        первый = проверка.прочитать()
        проверка.assertEqual(первый["граница"], len(проверка.заголовок))
        проверка.assertFalse(первый["полнота_подтверждена"])
        with проверка.источник.open("ab") as поток:
            поток.write(b"\n" + строка(команда("После оболочки.", 1)))
        второй = проверка.прочитать()
        проверка.assertTrue(второй["полнота_подтверждена"])
        проверка.assertEqual(len(второй["сообщения"]), 1)

    def test_смена_реализации_перечитывает_прежний_префикс(проверка):
        проверка.добавить(проверка.служебное(), команда("Сохрани.", 1))
        with mock.patch.object(читатель, "_РЕАЛИЗАЦИЯ", "0" * 64):
            прежний = проверка.прочитать()
        старый_кэш = проверка.кэш.read_bytes()
        без_записи = проверка.прочитать(без_записи=True)
        проверка.assertGreater(без_записи["профиль"]["разобрано_строк"], 0)
        проверка.assertEqual(проверка.кэш.read_bytes(), старый_кэш)
        новый = проверка.прочитать()
        повтор = проверка.прочитать()
        проверка.assertEqual(новый["сообщения"], прежний["сообщения"])
        проверка.assertEqual(новый["sha256"], прежний["sha256"])
        проверка.assertEqual(повтор["профиль"]["разобрано_строк"], 0)
        проверка.assertEqual(повтор["профиль"]["прочитано_байтов"], 0)
        проверка.источник.write_bytes(проверка.источник.read_bytes().replace("Сохрани".encode(), "Замени!".encode()))
        with mock.patch.object(читатель, "_РЕАЛИЗАЦИЯ", "1" * 64):
            with проверка.assertRaises(читатель.ОшибкаСообщений):
                проверка.прочитать()

    def test_кэш_границ_также_перепроверяется_при_смене_кода(проверка):
        проверка.добавить(проверка.служебное(), команда("Граница.", 1))
        снимок = проверка.прочитать()
        контексты = [обработчик.контекст_снимка(снимок)]
        кэш = проверка.база / "границы.json"
        with mock.patch.object(обработчик, "_РЕАЛИЗАЦИЯ", "0" * 64):
            обработчик.сверить_границы(проверка.источник, контексты, кэш=кэш)
        старые = кэш.read_bytes()
        профиль = обработчик.сверить_границы(проверка.источник, контексты, кэш=кэш, без_записи=True)
        проверка.assertGreater(профиль["прочитано_байтов"], 0)
        проверка.assertEqual(кэш.read_bytes(), старые)
        обработчик.сверить_границы(проверка.источник, контексты, кэш=кэш)
        проверка.assertEqual(обработчик.сверить_границы(проверка.источник, контексты, кэш=кэш)["прочитано_байтов"], 0)

    def test_новый_процесс_замечает_смену_байтов_реализации(проверка):
        дерево = проверка.база / "версия"
        for путь in [Path(читатель.__file__), читатель._ПУТЬ_КЛАССИФИКАТОРА,
                КАТАЛОГ.parent / "scripts" / "прочитать-сообщения-задачи.py"]:
            цель = дерево / путь.relative_to(КАТАЛОГ.parents[2])
            цель.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(путь, цель)
        проверка.добавить(проверка.служебное(), команда("Точная команда.", 1))
        программа = дерево / (КАТАЛОГ.parent / "scripts" / "прочитать-сообщения-задачи.py").relative_to(КАТАЛОГ.parents[2])
        def запустить():
            процесс = subprocess.run([sys.executable, "-B", str(программа), "--корень-репозитория", str(проверка.корень),
                "--codex-thread-id", ЗАДАЧА, "--исходник", str(проверка.источник), "--кэш", str(проверка.кэш)],
                capture_output=True, check=True)
            return json.loads(процесс.stdout)
        первый = запустить()
        прежний = json.loads(проверка.кэш.read_text())["данные"]
        реализация = дерево / Path(читатель.__file__).relative_to(КАТАЛОГ.parents[2])
        with реализация.open("ab") as поток:
            поток.write("\n# Контролируемая смена байтов реализации в изолированной фикстуре.\n".encode())
        второй = запустить()
        новый = json.loads(проверка.кэш.read_text())["данные"]
        проверка.assertNotEqual(прежний["реализация"], новый["реализация"])
        проверка.assertEqual(прежний["источник"], новый["источник"])
        проверка.assertEqual(первый["сообщения"], второй["сообщения"])
        проверка.assertEqual(первый["sha256"], второй["sha256"])
        проверка.assertGreater(второй["профиль"]["разобрано_строк"], 0)
        проверка.assertEqual(запустить()["профиль"]["разобрано_строк"], 0)


"""Один опыт N100 и один N200; времена включающих интервалов не суммируются."""
import argparse
import json
from pathlib import Path

from лаборатория_полной_копии_фасада import выполнить_опыт, байты, сохранить


def измерить(каталог, выход):
    каталог = Path(каталог).resolve(strict=True)
    выход = Path(выход).absolute()
    if list(каталог.iterdir()) or выход.exists():
        raise ValueError("Нужны пустой приватный каталог и новый выход")
    каталог.chmod(0o700)
    опыты = []
    for число in (100, 200):
        опыт = каталог / str(число)
        опыт.mkdir(mode=0o700)
        результат_опыта = выполнить_опыт(число, опыт)
        for шаг in ("захват", "предметная"):
            результат_опыта[шаг] = json.loads((опыт / ("трасса-" + шаг + ".json")).read_bytes())
        свидетельство = json.loads((опыт / "свидетельство-фасада").read_bytes())
        результат_опыта["разница_sha256"] = свидетельство["наблюдение"]["разница_sha256"]
        опыты.append(результат_опыта)
    assert опыты[0]["исходники_L"] == опыты[1]["исходники_L"]
    assert опыты[0]["разница_sha256"] == опыты[1]["разница_sha256"]
    результат = {"схема": "fum.профиль-полной-копии-фасада.1", "опытов_на_N": 1,
        "постоянных_файлов_контура": 30, "изменённых_путей": 31,
        "граница": "Локальная Git-фикстура без submodule. N обычных tracked-файлов плюс30 файлов контура. "
            "Одинаковый diff по31 пути: разделительный LF и оператор в каждом из30 исходников, "
            "изменение одного обычного файла. "
            "Setup, подготовка фасада, наблюдения, merge-фаза, эффект и свежий replay разделены. "
            "Вложенные интервалы не суммируются. Считается прямое создание Git-процесса через Popen; "
            "внутренние дочерние процессы Git не перехватываются. Синтетический допуск; "
            "это не время production и не доказательство ускорения.", "опыты": опыты}
    сохранить(выход, байты(результат))
    return {"схема": результат["схема"], "выход": str(выход), "N": [элемент["N"] for элемент in опыты],
        "git_первичного": [элемент["первичный"]["процессов_гит"] for элемент in опыты],
        "git_повтора": [элемент["повтор"]["процессов_гит"] for элемент in опыты]}


if __name__ == "__main__":
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--каталог", required=True)
    разбор.add_argument("--выход", required=True)
    параметры = разбор.parse_args()
    print(json.dumps(измерить(параметры.каталог, параметры.выход), ensure_ascii=False))

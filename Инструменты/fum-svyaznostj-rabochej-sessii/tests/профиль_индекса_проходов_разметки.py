"""Три свежих процесса с парным профилем трёх проходов на одном корпусе.

Успешные проходы на 0644: Git-корпус N16/32 и его сверки находятся вне таймера.
Полный слой включает вложенные инвентарь и позднюю сверку; интервалы не суммируются.
Это не профиль полного Creator, ROOT или холодного кэша ОС.
"""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import statistics
import subprocess
import sys
import types

import test_индекса_проходов_разметки as сценарии

КОРЕНЬ = Path(__file__).resolve().parents[3]
ОСНОВА = '432d5e07f4ce1ea8effcb14a5d1f3f3cc5fe3691'
ИСХОДНИК = 'Инструменты/fum-svyaznostj-rabochej-sessii/scripts/связность_независимого_журнала.py'
ТЕСТ = Path(сценарии.__file__).relative_to(КОРЕНЬ).as_posix()
ПРОФИЛЬ = Path(__file__).relative_to(КОРЕНЬ).as_posix()
ХЭШ_ОСНОВЫ = '7f8660c4c9d285697942e67f7382482654cd6b1c1512b5a91959c5630e8850f1'


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def канон(значение):
    return json.dumps(значение, ensure_ascii=False, sort_keys=True,
        separators=(',', ':')).encode()


def исходники():
    пути = {ИСХОДНИК, ТЕСТ, ПРОФИЛЬ}
    for модуль in list(sys.modules.values()):
        адрес = getattr(модуль, '__file__', None)
        if адрес:
            путь = Path(адрес).absolute()
            if путь.is_relative_to(КОРЕНЬ) and путь.suffix == '.py':
                пути.add(путь.relative_to(КОРЕНЬ).as_posix())
    return {путь: хэш((КОРЕНЬ / путь).read_bytes()) for путь in sorted(пути)}


def байты_основы(путь):
    return сценарии.связность.журнал()._гит(КОРЕНЬ, 'show', ОСНОВА + ':' + путь)


def отпечаток_стенда(снимок):
    return хэш(канон({путь: {'sha256': хэш(данные), 'идентичность': метка}
        for путь, (данные, метка) in снимок.items()}))


def рабочий(номер):
    сырые = байты_основы(ИСХОДНИК)
    assert хэш(сырые) == ХЭШ_ОСНОВЫ, 'подменена исходная версия consumer'
    прежний = types.ModuleType('прежняя_связность_профиля_разметки')
    прежний.__file__ = str(КОРЕНЬ / ИСХОДНИК)
    exec(compile(сырые, прежний.__file__, 'exec'), прежний.__dict__)
    варианты = [('прежний', прежний), ('новый', сценарии.связность)]
    if номер % 2:
        варианты.reverse()
    замеры, корпуса, проверенные_исходники = [], [], {}
    for число in (16, 32):
        with сценарии.стенд(число) as (фикс, _, _, состав, выбор):
            код = исходники()
            for путь, отпечаток in код.items():
                if путь not in {ИСХОДНИК, ТЕСТ, ПРОФИЛЬ}:
                    if путь not in проверенные_исходники:
                        assert хэш(байты_основы(путь)) == отпечаток, \
                            'изменена общая зависимость профиля: ' + путь
                    проверенные_исходники[путь] = отпечаток
            снимок = сценарии.история.снимок_без_эффектов(фикс.root)
            соседей = len(list((фикс.root / 'Журнал').iterdir()))
            корпуса.append({'папок_запросов': число, 'соседних_имён': соседей,
                'снимок_sha256': отпечаток_стенда(снимок),
                'состав_sha256': хэш(канон(состав))})
            for проход in ('инвентарь', 'поздний', 'слой'):
                ожидаемый = None
                for название, модуль in варианты:
                    замер, результат = сценарии.измерить(
                        модуль, фикс.root, состав, выбор, проход)
                    if проход == 'слой':
                        assert результат[0] == [], результат[0]
                    отпечаток = хэш(канон(результат))
                    if ожидаемый is None:
                        ожидаемый = отпечаток
                    assert ожидаемый == отпечаток, 'изменён исход парного вызова'
                    активные = ('инвентарь', 'основной', 'поздний') \
                        if проход == 'слой' else (проход,)
                    if название == 'новый':
                        for фаза, значения in замер['фазы'].items():
                            множитель = 2 if фаза in активные else 0
                            assert значения == {'перечисления': множитель,
                                'имена': множитель * соседей}, (проход, фаза, значения)
                    assert снимок == сценарии.история.снимок_без_эффектов(фикс.root), \
                        'вызов изменил байты, права, идентичность или Git стенда'
                    assert код == исходники(), 'исходники изменились во время замера'
                    замеры.append({'папок_запросов': число, 'соседних_имён': соседей,
                        'вариант': название, 'проход': проход, **замер,
                        'исход_sha256': отпечаток, 'без_эффектов': True})
    return {'процесс': номер, 'порядок': [имя for имя, _ in варианты],
        'среда': {'python': platform.python_version(), 'платформа': platform.platform()},
        'воспроизводимая_команда': ['python3.14', '-B', ПРОФИЛЬ, '--рабочий', str(номер)],
        'основа': ОСНОВА, 'исходник_основы_sha256': хэш(сырые),
        'исходники': исходники(), 'корпуса': корпуса, 'замеры': замеры}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument('--рабочий', type=int, choices=range(3))
    разбор.add_argument('--выход')
    параметры = разбор.parse_args()
    if параметры.рабочий is not None:
        print(json.dumps(рабочий(параметры.рабочий), ensure_ascii=False, sort_keys=True))
        return
    assert параметры.выход and not Path(параметры.выход).exists(), 'нужен новый файл результата'
    код = исходники()
    процессы = []
    for номер in range(3):
        ответ = subprocess.run([sys.executable, '-B', str(Path(__file__).resolve()),
            '--рабочий', str(номер)], capture_output=True, timeout=180)
        assert ответ.returncode == 0, ответ.stderr.decode()
        процессы.append(json.loads(ответ.stdout))
    assert код == исходники(), 'исходники родителя изменились'
    for процесс in процессы:
        assert процесс['исходники'] == процессы[0]['исходники']
        assert all(хэш((КОРЕНЬ / путь).read_bytes()) == значение
            for путь, значение in процесс['исходники'].items()), 'дрейф исходников worker'
    медианы = []
    for число in (16, 32):
        for проход in ('инвентарь', 'поздний', 'слой'):
            медианы.append({'папок_запросов': число, 'проход': проход,
                **{вариант: statistics.median(з['длительность_нс']
                    for п in процессы for з in п['замеры']
                    if з['папок_запросов'] == число and з['проход'] == проход
                    and з['вариант'] == вариант) for вариант in ('прежний', 'новый')}})
    итог = {'схема': 'fum.профиль-индекса-проходов-разметки.1',
        'граница': 'Успех на 0644, малый H/S: без подготовки, полного Creator, ROOT и холодного кэша ОС',
        'счётчики': 'Реальные вызовы Path.iterdir и выданные имена только точного W/Журнал',
        'интервалы': 'Слой включает инвентарь и позднюю сверку; вложенное время не складывается',
        'процессы': процессы, 'медианы_наносекунды': медианы}
    with Path(параметры.выход).open('x') as поток:
        json.dump(итог, поток, ensure_ascii=False, sort_keys=True, indent=2)
        поток.write('\n')
    print(json.dumps({'процессов': len(процессы),
        'медианы_наносекунды': медианы}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

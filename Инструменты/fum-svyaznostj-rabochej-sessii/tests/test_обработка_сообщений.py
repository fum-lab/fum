    def test_неизменный_источник_не_перечитывается_ради_старых_границ(проверка):
        снимок = проверка.остаток()
        проверка.сохранить(проверка.предложение(снимок), снимок)
        проверка.остаток()
        прочитано = []
        открыть = os.fdopen
        номер_узла_источника = проверка.источник.stat().st_ino
        class Счётчик:
            def __init__(экземпляр, поток):
                экземпляр.поток = поток
            def __enter__(экземпляр):
                экземпляр.поток.__enter__()
                return экземпляр
            def __exit__(экземпляр, *аргументы):
                return экземпляр.поток.__exit__(*аргументы)
            def __getattr__(экземпляр, имя):
                атрибут = getattr(экземпляр.поток, имя)
                if имя not in {"read", "readline"}:
                    return атрибут
                def подсчитать(*аргументы):
                    байты = атрибут(*аргументы)
                    прочитано.append(len(байты))
                    return байты
                return подсчитать
        def считать(дескриптор, *аргументы, **именованные):
            целевой = os.fstat(дескриптор).st_ino == номер_узла_источника
            поток = открыть(дескриптор, *аргументы, **именованные)
            return Счётчик(поток) if целевой else поток
        with mock.patch.object(os, "fdopen", side_effect=считать):
            итог = проверка.остаток()
        проверка.assertEqual(итог["остаток"], [])
        проверка.assertEqual(sum(прочитано), 0)


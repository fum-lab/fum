    def test_служебное_дописывание_при_сверке_границ_не_прерывает_остаток(проверка):
        снимок = проверка.остаток()
        проверка.сохранить(проверка.предложение(снимок), снимок)
        исходная = МОДУЛЬ.hashlib.sha256
        for кэшировать in (False, True):
            with проверка.subTest(кэшировать=кэшировать):
                вызвано = False
                def добавить_после_хэширования(данные=b""):
                    настоящий = исходная(данные)
                    def обновить(блок):
                        nonlocal вызвано
                        настоящий.update(блок)
                        if not вызвано:
                            вызвано = True
                            with проверка.источник.open("ab") as поток:
                                поток.write(строка({"type": "event_msg", "payload": {"type": "token_count"}}))
                    обёртка = mock.Mock(wraps=настоящий)
                    обёртка.attach_mock(mock.Mock(side_effect=обновить), "update")
                    return обёртка
                сверка = МОДУЛЬ.сверить_границы
                def сверить_с_дописыванием(*аргументы, **параметры):
                    with mock.patch.object(МОДУЛЬ.hashlib, "sha256", side_effect=добавить_после_хэширования):
                        return сверка(*аргументы, **параметры)
                with mock.patch.object(МОДУЛЬ, "сверить_границы", side_effect=сверить_с_дописыванием):
                    итог = МОДУЛЬ.получить_остаток(проверка.источник, ЗАДАЧА,
                        корень_репозитория=проверка.корень, кэш=проверка.кэш, кэшировать_границы=кэшировать)

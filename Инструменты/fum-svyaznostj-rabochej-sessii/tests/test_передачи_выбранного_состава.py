"""S поставлен отдельным коммитом, а HEAD принимающего писателя остаётся H."""
import hashlib
import json
import os
from pathlib import Path
import sys
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_независимой_контрольной_точки as исходный

связность = исходный.связность


class ПередачаВыбранногоСостава(unittest.TestCase):
    def стенд(сам, фасад=False):
        if фасад:
            помощник = исходный.НезависимыйФасад()
            модуль, пример, _, вход, выбор = помощник.стенд()
            сам.addCleanup(помощник.doCleanups)
        else:
            пример = исходный.РеальныйНезависимыйСоздатель()
            пример.setUp()
            сам.addCleanup(пример.doCleanups)
            модуль = вход = выбор = None
        корень = пример.ф.корень
        родитель = пример.ф.гит('rev-parse', 'HEAD').strip()
        состав = пример.ж.состав_принятого_дерева(корень, родитель)
        сырые = (json.dumps(состав, ensure_ascii=False, sort_keys=True) + '\n').encode()
        (корень / пример.ж.ПУТЬ_СОСТАВА).write_bytes(сырые)
        (корень / пример.ж.ПУТЬ_ИНДЕКСА).write_bytes(
            пример.ж.построить_принятый_индекс(корень, состав)['байты'])
        пример.ф.гит('add', '--', пример.ж.ПУТЬ_СОСТАВА, пример.ж.ПУТЬ_ИНДЕКСА)
        пример.ф.гит('commit', '-qm', 'Поставить состав отдельно от принимающего HEAD')
        поставка = пример.ф.гит('rev-parse', 'HEAD').strip()
        # Только временная Git-фикстура: сохраняем новые рабочие байты S.
        пример.ф.гит('update-ref', 'HEAD', родитель, поставка)
        пример.ф.гит('read-tree', родитель)
        пример.выбранный = {'коммит': поставка, 'путь': пример.ж.ПУТЬ_СОСТАВА,
            'sha256': hashlib.sha256(сырые).hexdigest()}
        пример.п.update(исходный_коммит=родитель, родители=[родитель])
        пример.п['контракт_журнала']['состав'] = пример.выбранный
        пример.п['разрешённые_цели'] += [пример.ж.ПУТЬ_СОСТАВА, пример.ж.ПУТЬ_ИНДЕКСА]
        if фасад:
            Path(вход['вход_коммита']).write_bytes(модуль.байты(пример.п))
            Path(вход['контракт_журнала']).write_bytes(модуль.байты(пример.п['контракт_журнала']))
            Path(выбор).write_bytes(модуль.байты(пример.выбранный))
            наполнение = json.loads(Path(вход['наполнение']).read_bytes())
            разрешение = Path(наполнение['разрешение']['путь'])
            разрешение.write_bytes(модуль.байты(пример.п['разрешённые_цели']))
            наполнение['разрешение']['sha256'] = hashlib.sha256(разрешение.read_bytes()).hexdigest()
            Path(вход['наполнение']).write_bytes(модуль.байты(наполнение))
        сам.assertNotEqual(поставка, родитель)
        сам.assertEqual(родитель, пример.ф.гит('rev-parse', 'HEAD').strip())
        return пример, модуль, вход, выбор

    def проверить(сам, пример, выбор=None):
        связность.проверить_область_записей(пример.п,
            выбранный_состав=пример.выбранный if выбор is None else выбор)

    def test_отдельная_поставка_проходит_без_изменения_вершины_и_рабочих_байтов(сам):
        пример, _, _, _ = сам.стенд()
        до = исходный.снимок(пример.ф.корень)
        сам.проверить(пример)
        сам.assertEqual(до, исходный.снимок(пример.ф.корень))

    def test_копия_во_входе_не_заменяет_внешний_выбор(сам):
        пример, _, _, _ = сам.стенд()
        до = исходный.снимок(пример.ф.корень)
        with сам.assertRaises(ValueError):
            связность.проверить_область_записей(пример.п)
        сам.assertEqual(до, исходный.снимок(пример.ф.корень))

    def test_подмена_внешнего_выбора_или_его_копии_отвергается(сам):
        пример, _, _, _ = сам.стенд()
        for поле, значение in [('sha256', '0' * 64),
                ('коммит', пример.п['исходный_коммит'])]:
            with сам.subTest(поле=поле), сам.assertRaises(ValueError):
                сам.проверить(пример, {**пример.выбранный, поле: значение})
        пример.п['контракт_журнала']['состав'] = {**пример.выбранный, 'sha256': '0' * 64}
        with сам.assertRaises(ValueError):
            сам.проверить(пример)

    def test_живые_байты_и_строгий_режим_состава(сам):
        пример, _, _, _ = сам.стенд()
        файл = пример.ф.корень / пример.ж.ПУТЬ_СОСТАВА
        сырые = файл.read_bytes()
        файл.write_bytes(сырые + b'\n')
        with сам.assertRaises(ValueError): сам.проверить(пример)
        файл.write_bytes(сырые)
        файл.chmod(0o600)
        with сам.assertRaises(ValueError): сам.проверить(пример)

    def test_состав_не_может_подмениться_во_время_инвентаря(сам):
        пример, _, _, _ = сам.стенд()
        файл = пример.ф.корень / пример.ж.ПУТЬ_СОСТАВА
        сырые = файл.read_bytes()
        прежний = связность.инвентарь_разметки
        def инвентарь_с_подменой(*аргументы, **поля):
            файл.write_bytes(сырые + b'\n')
            результат = прежний(*аргументы, **поля)
            файл.write_bytes(сырые)
            return результат
        with mock.patch.object(связность, 'инвентарь_разметки', инвентарь_с_подменой):
            with сам.assertRaises(ValueError): сам.проверить(пример)

    def test_состав_не_может_быть_символической_или_жёсткой_ссылкой(сам):
        пример, _, _, _ = сам.стенд()
        файл = пример.ф.корень / пример.ж.ПУТЬ_СОСТАВА
        сохранённый = файл.with_suffix('.сохранённый')
        файл.rename(сохранённый)
        файл.symlink_to(сохранённый.name)
        with сам.assertRaises(ValueError): сам.проверить(пример)
        файл.unlink()
        os.link(сохранённый, файл)
        with сам.assertRaises(ValueError): сам.проверить(пример)

    def test_поздняя_подмена_обнаруживается_даже_при_возврате_байтов_и_времени_изменения(сам):
        пример, _, _, _ = сам.стенд()
        файл = пример.ф.корень / пример.ж.ПУТЬ_СОСТАВА
        сырые = файл.read_bytes(); мета = файл.stat()
        прежняя = связность.сверить_снимки_разметки
        def сверка_после_подмены(*аргументы, **поля):
            файл.write_bytes(сырые + b'\n'); файл.write_bytes(сырые)
            os.utime(файл, ns=(мета.st_atime_ns, мета.st_mtime_ns))
            return прежняя(*аргументы, **поля)
        with mock.patch.object(связность, 'сверить_снимки_разметки', сверка_после_подмены):
            with сам.assertRaises(ValueError): сам.проверить(пример)

    def test_новая_запись_вне_области_не_получает_разрешения(сам):
        пример, _, _, _ = сам.стенд()
        (пример.ф.корень / 'вне-области.txt').write_text('чужая запись\n')
        with сам.assertRaises(ValueError): сам.проверить(пример)

    def test_создатель_получает_тот_же_независимый_выбор(сам):
        пример, _, _, _ = сам.стенд()
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=исходный.база.ЗАДАЧА):
            пример.м.подготовить(пример.п, выбранный_состав=пример.выбранный)
        подготовка = json.loads(Path(пример.п['подготовка']).read_bytes())
        сам.assertEqual('fum.подготовленный-коммит.11', подготовка['схема'])
        сам.assertEqual(пример.выбранный, подготовка['привязка_журнала']['выбранный_состав'])

    def test_фасад_передаёт_выбор_при_плане_и_повторной_сверке(сам):
        пример, модуль, вход, выбор = сам.стенд(фасад=True)
        до = исходный.снимок(пример.ф.корень)
        with mock.patch.dict(os.environ, CODEX_THREAD_ID=исходный.база.ЗАДАЧА):
            план = модуль.построить_план(вход, выбранный_состав=выбор)
            модуль._сверить_новую_границу(вход, план, выбор)
        сам.assertEqual(до, исходный.снимок(пример.ф.корень))


if __name__ == '__main__':
    unittest.main()

class ПередачаВыбранногоСостава(unittest.TestCase):
    def стенд(сам, фасад=False):
        if фасад:
            помощник = исходный.НезависимыйФасад()
            модуль, пример, _, вход, выбор = помощник.стенд()
            сам.addCleanup(помощник.doCleanups)
        else:
            пример = исходный.РеальныйНезависимыйСоздатель()
            пример.setUp()
            сам.addCleanup(пример.doCleanups)
            модуль = вход = выбор = None
        корень = пример.ф.корень
        родитель = пример.ф.гит('rev-parse', 'HEAD').strip()
        состав = пример.ж.состав_принятого_дерева(корень, родитель)
        сырые = (json.dumps(состав, ensure_ascii=False, sort_keys=True) + '\n').encode()
        (корень / пример.ж.ПУТЬ_СОСТАВА).write_bytes(сырые)
        (корень / пример.ж.ПУТЬ_ИНДЕКСА).write_bytes(
            пример.ж.построить_принятый_индекс(корень, состав)['байты'])
        пример.ф.гит('add', '--', пример.ж.ПУТЬ_СОСТАВА, пример.ж.ПУТЬ_ИНДЕКСА)
        пример.ф.гит('commit', '-qm', 'Поставить состав отдельно от принимающего HEAD')
        поставка = пример.ф.гит('rev-parse', 'HEAD').strip()
        # Только временная Git-фикстура: сохраняем новые рабочие байты S.
        пример.ф.гит('update-ref', 'HEAD', родитель, поставка)
        пример.ф.гит('read-tree', родитель)
        пример.выбранный = {'коммит': поставка, 'путь': пример.ж.ПУТЬ_СОСТАВА,
            'sha256': hashlib.sha256(сырые).hexdigest()}
        пример.п.update(исходный_коммит=родитель, родители=[родитель])
        пример.п['контракт_журнала']['состав'] = пример.выбранный
        пример.п['разрешённые_цели'] += [пример.ж.ПУТЬ_СОСТАВА, пример.ж.ПУТЬ_ИНДЕКСА]
        if фасад:
            Path(вход['вход_коммита']).write_bytes(модуль.байты(пример.п))
            Path(вход['контракт_журнала']).write_bytes(модуль.байты(пример.п['контракт_журнала']))
            Path(выбор).write_bytes(модуль.байты(пример.выбранный))
            наполнение = json.loads(Path(вход['наполнение']).read_bytes())
            разрешение = Path(наполнение['разрешение']['путь'])
            разрешение.write_bytes(модуль.байты(пример.п['разрешённые_цели']))
            наполнение['разрешение']['sha256'] = hashlib.sha256(разрешение.read_bytes()).hexdigest()
            Path(вход['наполнение']).write_bytes(модуль.байты(наполнение))
        сам.assertNotEqual(поставка, родитель)
        сам.assertEqual(родитель, пример.ф.гит('rev-parse', 'HEAD').strip())
        return пример, модуль, вход, выбор


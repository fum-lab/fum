        итог = сам.м.исполнить_команду([sys.executable, '-B', '-c', профиль.ОБОЛОЧКА,
            str(диагностика), str(сценарий)], сам.ф.корень)
        сам.assertEqual((7, 'исходный stdout\n', ''), (итог['код'], итог['stdout'], итог['stderr']))
        сам.assertEqual('исходный stdout\n'.encode(), base64.b64decode(итог['каналы']['stdout']['base64']))
        сам.assertTrue(диагностика.exists())
        сам.assertEqual(b'', диагностика.read_bytes())


    def test_полные_каналы_приватны_события_замкнуты(сам):
        секрет = 'КОНТРОЛЬ-КАНАЛА-3fbf0261'
        сам.ф.тест.write_text("import unittest,sys\nclass Проверка(unittest.TestCase):\n"
            f" def test_каналы(сам):\n  print({секрет!r})\n  print({секрет!r},file=sys.stderr)\n")
        цель = сам.ф.тест.relative_to(сам.ф.корень).as_posix()
        if цель not in сам.ф.п['разрешённые_цели']:
            сам.ф.п['разрешённые_цели'].append(цель)
            сам.ф.сохранить('вход-root.json',сам.ф.п)
            сам.ф.сохранить('разрешение-root.json',сам.ф.п['разрешённые_цели'])
            сам.ф.наполнение['разрешение']['sha256'] = сам.м.хэш(байты(сам.ф.п['разрешённые_цели']))
            сам.ф.сохранить('наполнение-root.json',сам.ф.наполнение)
        события = []; итог = сам.запустить(события.append)
        сам.assertEqual(0,итог['код'],итог)
        сам.assertEqual(0o600,сам.выход.stat().st_mode & 0o777)
        полный = json.loads(сам.выход.read_bytes())
        сам.assertIn(секрет,json.dumps(полный,ensure_ascii=False))
        for стадия in полный['стадии']:
            if 'каналы' in стадия:
                for канал in стадия['каналы'].values():
                    сырые=base64.b64decode(канал['base64'],validate=True)
                    сам.assertEqual(len(сырые),канал['байтов'])
                    сам.assertEqual(сам.м.хэш(сырые),канал['sha256'])
        сам.assertEqual(события,итог['события'])
        сам.assertEqual(list(range(1,len(события)+1)),[э['порядок'] for э in события])
        for э in события:
            сам.assertEqual({'идентификатор','порядок','состояние','код','длительность_наносекунды'},set(э))
            сам.assertIn(э['идентификатор'],сам.м.ИДЕНТИФИКАТОРЫ_СТАДИЙ)
            сам.assertGreaterEqual(э['длительность_наносекунды'],0)
        компактный = json.dumps(итог,ensure_ascii=False)
        for контроль in (секрет,base64.b64encode(секрет.encode()).decode(),'аргументы','stdout','stderr','снимок'):
            сам.assertNotIn(контроль,компактный)
        сам.assertFalse(итог['коммит_создан'])


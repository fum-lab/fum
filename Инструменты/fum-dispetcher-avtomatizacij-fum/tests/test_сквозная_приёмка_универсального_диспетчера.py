from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
import unittest
from copy import deepcopy
from pathlib import Path


КОРЕНЬ_АВТОМАТИЗАЦИИ = Path(__file__).resolve().parents[1]
КОРЕНЬ_РЕПОЗИТОРИЯ = КОРЕНЬ_АВТОМАТИЗАЦИИ.parents[1]
СЦЕНАРИЙ = (
    КОРЕНЬ_АВТОМАТИЗАЦИИ / "scripts" / "диспетчер-автоматизаций.py"
)
СХЕМА = КОРЕНЬ_АВТОМАТИЗАЦИИ / "схемы" / "реестр-заданий-v1.schema.json"
КАНОНИЧЕСКИЙ_РЕЕСТР = (
    КОРЕНЬ_РЕПОЗИТОРИЯ
    / "Планирование"
    / "реестры-заданий-автоматизаций"
    / "master.json"
)
class СквознаяПриёмкаУниверсальногоДиспетчера(unittest.TestCase):
    def выполнить(
        сам,
        корень: Path,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(СЦЕНАРИЙ), *аргументы],
            cwd=корень,
            check=False,
            capture_output=True,
            text=True,
        )

    def выполнить_гит(
        сам,
        корень: Path,
        *аргументы: str,
    ) -> str:
        результат = subprocess.run(
            ["git", "-C", str(корень), *аргументы],
            check=False,
            capture_output=True,
            text=True,
        )
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        return результат.stdout

    def записать_json(сам, путь: Path, значение: object) -> None:
        путь.write_text(
            json.dumps(
                значение,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )

    def задание_без_эффекта(
        сам,
        шаблон: dict[str, object],
        идентификатор: str,
        состояние: str,
        приоритет: int,
    ) -> dict[str, object]:
        задание = deepcopy(шаблон)
        задание["job_id"] = идентификатор
        задание["приоритет"] = приоритет
        задание["адаптер"] = {
            "контракт": "пробник-без-эффекта.1",
            "тип": "пробник_расписания",
        }
        задание["условия_допуска"] = []
        задание["состояние"] = состояние
        задание["эффект"] = {
            "класс": "только_чтение",
            "политика": "без_побочных_эффектов",
        }
        задание["исполнитель"] = {
            "контракт": "локальный-симулятор.1",
            "тип": "локальный_пробник",
        }
        задание["политика_ошибки"]["повтор"] = "вручную"
        return задание

    def снимок_читаемого_состояния(сам, корень: Path) -> dict[str, object]:
        путь_индекса = корень / ".git" / "index"
        return {
            "HEAD": сам.выполнить_гит(корень, "rev-parse", "HEAD"),
            "ветка": сам.выполнить_гит(корень, "symbolic-ref", "HEAD"),
            "индекс": hashlib.sha256(путь_индекса.read_bytes()).hexdigest(),
            "ссылки": сам.выполнить_гит(
                корень,
                "for-each-ref",
                "--format=%(refname) %(objectname)",
            ),
            "статус": сам.выполнить_гит(
                корень,
                "status",
                "--porcelain=v1",
                "-z",
            ),
        }

    def test_единый_реестр_выбирает_по_одному_без_голодания_и_условия_публикации(
        сам,
    ) -> None:
        с_временным_каталогом = tempfile.TemporaryDirectory()
        сам.addCleanup(с_временным_каталогом.cleanup)
        корень = Path(с_временным_каталогом.name)
        инициализация = subprocess.run(
            ["git", "init", "--initial-branch=master", str(корень)],
            check=False,
            capture_output=True,
            text=True,
        )
        сам.assertEqual(инициализация.returncode, 0, инициализация.stderr)
        сам.выполнить_гит(корень, "config", "user.name", "FUM Tests")
        сам.выполнить_гит(
            корень,
            "config",
            "user.email",
            "fum-tests@example.invalid",
        )
        (корень / "README.md").write_text("# FUM\n", encoding="utf-8")

        реестр = json.loads(КАНОНИЧЕСКИЙ_РЕЕСТР.read_text(encoding="utf-8"))
        шаблон = реестр["задания"][0]
        реестр["идентификатор_реестра"] = "приёмка.универсальный-диспетчер"
        реестр["поколение_реестра"] = 4
        реестр["задания"].extend(
            [
                сам.задание_без_эффекта(
                    шаблон,
                    "master.acceptance-paused",
                    "paused",
                    20,
                ),
                сам.задание_без_эффекта(
                    шаблон,
                    "master.acceptance-blocked",
                    "blocked",
                    30,
                ),
            ]
        )
        условия = {
            условие["наблюдение"]: True
            for задание in реестр["задания"][:2]
            for условие in задание["условия_допуска"]
        }
        наблюдения = {
            "версия_схемы": 1,
            "момент": "2026-08-05T12:05:00Z",
            "условия": условия,
            "подтверждённые_события": {
                "завершение_runtime_ready_commit_handoff": 5,
            },
        }
        путь_реестра = корень / "реестр.json"
        путь_схемы = корень / "схема.json"
        путь_наблюдений = корень / "наблюдения.json"
        сам.записать_json(путь_реестра, реестр)
        путь_схемы.write_bytes(СХЕМА.read_bytes())
        сам.записать_json(путь_наблюдений, наблюдения)
        сам.выполнить_гит(корень, "add", "--", ".")
        сам.выполнить_гит(корень, "commit", "-m", "Создать сквозную фикстуру")

        снимок_до = сам.снимок_читаемого_состояния(корень)
        симуляция = сам.выполнить(
            корень,
            "симулировать",
            "--корень-рабочей-копии",
            str(корень),
            "--реестр",
            str(путь_реестра),
            "--схема",
            str(путь_схемы),
            "--наблюдения",
            str(путь_наблюдений),
            "--json",
        )
        сам.assertEqual(симуляция.returncode, 0, симуляция.stderr)
        статусы = {
            задание["job_id"]: задание["статус"]
            for задание in json.loads(симуляция.stdout)["задания"]
        }
        сам.assertEqual(статусы["master.next-step"], "готово")
        сам.assertEqual(статусы["master.completed-step-analysis"], "готово")
        сам.assertEqual(статусы["master.acceptance-paused"], "приостановлено")
        сам.assertEqual(статусы["master.acceptance-blocked"], "заблокировано")

        первый_выбор = сам.выполнить(
            корень,
            "выбрать",
            "--корень-рабочей-копии",
            str(корень),
            "--реестр",
            str(путь_реестра),
            "--схема",
            str(путь_схемы),
            "--наблюдения",
            str(путь_наблюдений),
            "--json",
        )
        сам.assertEqual(первый_выбор.returncode, 0, первый_выбор.stderr)
        первый = json.loads(первый_выбор.stdout)
        сам.assertEqual(первый["состояние"], "выбрано")
        сам.assertEqual(первый["число_готовых"], 2)
        сам.assertEqual(первый["job_id"], "master.completed-step-analysis")
        сам.assertEqual(сам.снимок_читаемого_состояния(корень), снимок_до)

        аналитическое = next(
            задание
            for задание in реестр["задания"]
            if задание["job_id"] == "master.completed-step-analysis"
        )
        курсор = аналитическое["курсор_результата"]
        курсор["последнее_число_подтверждённых_событий"] = 5
        курсор["следующий_порог"] = 10
        курсор["последний_подтверждённый_аналитический_результат"] = {
            "идентификатор": "sha256:" + "a" * 64,
            "путь": "Оценки/аналитика-завершённых-запусков/master/"
            "master.completed-step-analysis/0000000001-0000000005.md",
            "content_sha256": "sha256:" + "b" * 64,
            "конец_диапазона": 5,
        }
        сам.записать_json(путь_реестра, реестр)
        сам.выполнить_гит(корень, "add", "--", "реестр.json")
        сам.выполнить_гит(корень, "commit", "-m", "Подтвердить первый порог")
        снимок_после_курсора = сам.снимок_читаемого_состояния(корень)
        второй_выбор = сам.выполнить(
            корень,
            "выбрать",
            "--корень-рабочей-копии",
            str(корень),
            "--реестр",
            str(путь_реестра),
            "--схема",
            str(путь_схемы),
            "--наблюдения",
            str(путь_наблюдений),
            "--json",
        )
        сам.assertEqual(второй_выбор.returncode, 0, второй_выбор.stderr)
        второй = json.loads(второй_выбор.stdout)
        сам.assertEqual(второй["состояние"], "выбрано")
        сам.assertEqual(второй["число_готовых"], 1)
        сам.assertEqual(второй["job_id"], "master.next-step")
        сам.assertEqual(
            сам.снимок_читаемого_состояния(корень),
            снимок_после_курсора,
        )

        сам.assertEqual(
            {
                задание["job_id"]: (
                    задание["адаптер"]["тип"],
                    задание["эффект"]["класс"],
                    задание["эффект"]["политика"],
                )
                for задание in реестр["задания"]
            },
            {
                "master.next-step": (
                    "следующий_шаг_ветки",
                    "изменение_репозитория",
                    "только_через_очередь_и_локальную_передачу_коммита",
                ),
                "master.completed-step-analysis": (
                    "аналитика_завершённых_шагов",
                    "изменение_репозитория",
                    "только_через_очередь_и_локальную_передачу_коммита",
                ),
                "master.acceptance-paused": (
                    "пробник_расписания",
                    "только_чтение",
                    "без_побочных_эффектов",
                ),
                "master.acceptance-blocked": (
                    "пробник_расписания",
                    "только_чтение",
                    "без_побочных_эффектов",
                ),
            },
        )
        заблокированное = next(
            задание
            for задание in реестр["задания"]
            if задание["job_id"] == "master.acceptance-blocked"
        )
        сам.assertEqual(заблокированное["эффект"]["класс"], "только_чтение")

if __name__ == "__main__":
    unittest.main()

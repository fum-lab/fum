    def сформировать(
        сам,
        намерение: str,
        данные: dict[str, object],
        *,
        реестр: dict[str, object] | None = None,
        идентификатор_сообщения: str = ИДЕНТИФИКАТОР_СООБЩЕНИЯ,
    ) -> dict[str, object]:
        результат = сформировать_предложение(
            сам.реестр if реестр is None else реестр,
            намерение,
            данные,
            идентификатор_сообщения,
            ХЭШ_СООБЩЕНИЯ,
            ОЖИДАЕМАЯ_ВЕРШИНА,
        )
        сам.assertIsInstance(результат, dict)
        return результат


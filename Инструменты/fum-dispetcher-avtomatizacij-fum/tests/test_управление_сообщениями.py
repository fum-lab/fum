    def test_пауза_и_возобновление_применяются_с_точными_поколениями(
        сам,
    ) -> None:
        пауза = сам.сформировать(
            "приостановить_задание",
            {"job_id": "master.next-step"},
        )

        состояние, после_паузы = применить_предложение_к_реестру(
            сам.реестр,
            пауза,
            {ПОДТВЕРЖДЕНИЕ_ПРИМЕНЕНИЯ},
        )

        сам.assertEqual(состояние, "применено")
        сам.assertEqual(сам.реестр["поколение_реестра"], 2)
        сам.assertEqual(после_паузы["поколение_реестра"], 3)
        задание = найти_задание(после_паузы, "master.next-step")
        сам.assertEqual(задание["состояние"], "paused")
        сам.assertEqual(задание["поколение"], 2)
        сам.assertEqual(задание["защита_поколения"]["поколение"], 2)

        возобновление = сам.сформировать(
            "возобновить_задание",
            {"job_id": "master.next-step"},
            реестр=после_паузы,
            идентификатор_сообщения="message-002",
        )
        состояние, после_возобновления = применить_предложение_к_реестру(
            после_паузы,
            возобновление,
            {ПОДТВЕРЖДЕНИЕ_ПРИМЕНЕНИЯ},
        )

        сам.assertEqual(состояние, "применено")
        сам.assertEqual(после_возобновления["поколение_реестра"], 4)
        задание = найти_задание(после_возобновления, "master.next-step")
        сам.assertEqual(задание["состояние"], "active")
        сам.assertEqual(задание["поколение"], 3)
        сам.assertEqual(задание["защита_поколения"]["поколение"], 3)


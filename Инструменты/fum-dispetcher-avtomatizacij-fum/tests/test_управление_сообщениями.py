def вычислить_хэш_реестра(реестр: dict[str, object]) -> str:
    байты = json.dumps(
        реестр,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return "sha256:" + hashlib.sha256(байты).hexdigest()


def найти_задание(
    реестр: dict[str, object],
    идентификатор: str,
) -> dict[str, object]:
    задания = реестр["задания"]
    if not isinstance(задания, list):
        raise AssertionError("фикстура реестра не содержит массив заданий")
    for сырое_задание in задания:
        if not isinstance(сырое_задание, dict):
            continue
        if сырое_задание.get("job_id") == идентификатор:
            return сырое_задание
    raise AssertionError(f"задание {идентификатор} не найдено")



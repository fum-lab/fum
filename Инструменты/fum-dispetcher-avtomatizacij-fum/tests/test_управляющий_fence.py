        код_начала, _ = начать_управление(
            str(корень),
            str(путь_реестра),
            предложение,
            ИДЕНТИФИКАТОР_ЗАДАЧИ,
            ПОКОЛЕНИЕ_ОЧЕРЕДИ,
        )

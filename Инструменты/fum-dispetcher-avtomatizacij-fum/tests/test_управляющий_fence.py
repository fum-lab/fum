    def объект_управления(сам, корень: Path) -> str | None:
        строки = сам.выполнить_команду_гит(
            корень,
            "for-each-ref",
            "--format=%(objectname)",
            ПРОСТРАНСТВО_УПРАВЛЕНИЯ,
        ).stdout.splitlines()
        сам.assertLessEqual(len(строки), 1)
        return строки[0] if строки else None

    def проверить_публичный_ответ(
        сам,
        ответ: dict[str, object],
        ожидаемое_состояние: str,
        *секреты: str,
    ) -> None:
        сам.assertEqual(ответ, {"состояние": ожидаемое_состояние})
        представление = json.dumps(ответ, ensure_ascii=False)
        for секрет in секреты:
            сам.assertNotIn(секрет, представление)
        for поле in (
            "task_id",
            "generation",
            "ticket_id",
            "queue_ref",
            "идентификатор_предложения",
        ):
            сам.assertNotIn(поле, представление)


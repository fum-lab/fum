    def выполнить(
        сам,
        корень: Path,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(СЦЕНАРИЙ), *аргументы],
            cwd=корень,
            check=False,
            capture_output=True,
            text=True,
        )

    def выполнить_гит(
        сам,
        корень: Path,
        *аргументы: str,
        вход: str | None = None,
    ) -> subprocess.CompletedProcess[str]:
        результат = subprocess.run(
            ["git", "-C", str(корень), *аргументы],
            check=False,
            capture_output=True,
            text=True,
            input=вход,
        )
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        return результат

    def выполнить_очередь(
        сам,
        корень: Path,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(СЦЕНАРИЙ_ОЧЕРЕДИ), *аргументы],
            cwd=корень,
            check=False,
            capture_output=True,
            text=True,
        )

    def записать_объект(сам, путь: Path, значение: object) -> None:
        путь.write_text(
            json.dumps(
                значение,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )


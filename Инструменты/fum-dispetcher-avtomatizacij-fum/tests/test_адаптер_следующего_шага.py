    def подготовить_проверенный_запуск(
        сам,
        *,
        формат_объектов: str | None = None,
    ) -> tuple[
        Path,
        dict[str, object],
        str,
        str,
        str,
        list[str],
    ]:
        корень, реестр, схема, наблюдения, выбор = сам.создать_репозиторий(
            формат_объектов=формат_объектов,
        )
        попытка = str(uuid.uuid4())
        идентификатор_задачи = "actual-root-task"
        поколение_очереди = str(uuid.uuid4())
        сам.подготовить_создание(
            корень,
            реестр,
            схема,
            наблюдения,
            выбор,
            попытка,
            "created-thread-id",
        )
        аргументы = сам.аргументы_ограждения_запуска(
            корень,
            выбор,
            попытка,
        )
        привязка = сам.выполнить(
            корень,
            "bind-run",
            *аргументы,
            "--task-id",
            идентификатор_задачи,
            "--json",
        )
        сам.assertEqual(привязка.returncode, 0, привязка.stderr)
        сам.записать_очередь(
            корень,
            str(выбор["branch_ref"]),
            идентификатор_задачи,
            поколение_очереди,
            str(выбор["selection_head"]),
        )
        проверка = сам.выполнить(
            корень,
            "verify-run",
            *аргументы,
            "--task-id",
            идентификатор_задачи,
            "--generation",
            поколение_очереди,
            "--json",
        )
        сам.assertEqual(проверка.returncode, 0, проверка.stderr)
        return (
            корень,
            выбор,
            идентификатор_задачи,
            поколение_очереди,
            попытка,
            аргументы,
        )


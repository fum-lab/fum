    def подготовить_исторический_запуск_с_чужой_проекцией(
        сам,
        *,
        записать_правильный_журнал: bool,
    ) -> tuple[
        Path,
        dict[str, object],
        dict[str, object],
        list[str],
        str,
    ]:
        (
            корень,
            выбор,
            идентификатор_задачи,
            поколение_очереди,
            _попытка,
            аргументы,
        ) = сам.подготовить_проверенный_запуск()
        новая_вершина = сам.создать_коммит_результата(корень)
        завершение = {
            "kind": "committed",
            "task_id": идентификатор_задачи,
            "generation": поколение_очереди,
            "base_head": str(выбор["selection_head"]),
            "head": новая_вершина,
            "completed_at": "2026-08-05T12:06:00.000Z",
        }
        if записать_правильный_журнал:
            сам.записать_журнал_завершений(
                корень,
                str(выбор["branch_ref"]),
                завершение,
            )
        чужое = {
            "kind": "finished_clean",
            "task_id": "later-root-task",
            "generation": str(uuid.uuid4()),
            "head": новая_вершина,
            "completed_at": "2026-08-05T12:07:00.000Z",
        }
        сам.записать_очередь(
            корень,
            str(выбор["branch_ref"]),
            "later-root-task",
            str(чужое["generation"]),
            новая_вершина,
            завершение=чужое,
        )
        return корень, выбор, завершение, аргументы, новая_вершина

    def test_канонический_реестр_содержит_ровно_один_активный_адаптер(
        сам,
    ) -> None:
        реестр = json.loads(КАНОНИЧЕСКИЙ_РЕЕСТР.read_text(encoding="utf-8"))


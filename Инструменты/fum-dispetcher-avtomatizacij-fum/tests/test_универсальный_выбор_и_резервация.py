class УниверсальныйВыборИРезервация(unittest.TestCase):
    def выполнить(
        сам,
        корень: Path,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(СЦЕНАРИЙ), *аргументы],
            cwd=корень,
            check=False,
            capture_output=True,
            text=True,
        )

    def выполнить_гит(
        сам,
        корень: Path,
        *аргументы: str,
        вход: str | None = None,
    ) -> subprocess.CompletedProcess[str]:
        результат = subprocess.run(
            ["git", "-C", str(корень), *аргументы],
            check=False,
            capture_output=True,
            text=True,
            input=вход,
        )
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        return результат

    def записать_структуру(сам, путь: Path, значение: object) -> None:
        путь.write_text(
            json.dumps(
                значение,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )

    def установить_запись_сброса_очереди(сам, корень: Path) -> str:
        запись = {"схема": "fum.сброс-состояния-FIFO.1"}
        объект = сам.выполнить_гит(
            корень,
            "hash-object",
            "-w",
            "--stdin",
            вход=json.dumps(
                запись,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
            )
            + "\n",
        ).stdout.strip()
        ссылка = ссылка_очереди(корень)
        сам.выполнить_гит(корень, "update-ref", ссылка, объект)
        return ссылка

    def снимок_служебных_ссылок(сам, корень: Path) -> str:
        return сам.выполнить_гит(
            корень,
            "for-each-ref",
            "--format=%(refname) %(objectname)",
            "refs/fum/",
        ).stdout

    def создать_временный_репозиторий(
        сам,
        реестр: dict[str, object] | None = None,
        наблюдения: dict[str, object] | None = None,
    ) -> tuple[Path, Path, Path, Path]:
        временный_каталог = tempfile.TemporaryDirectory()
        сам.addCleanup(временный_каталог.cleanup)
        корень = Path(временный_каталог.name)
        результат = subprocess.run(
            ["git", "init", "--initial-branch=master", str(корень)],
            check=False,
            capture_output=True,
            text=True,
        )
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        сам.выполнить_гит(корень, "config", "user.name", "FUM Tests")
        сам.выполнить_гит(
            корень,
            "config",
            "user.email",
            "fum-tests@example.invalid",
        )
        (корень / "README.md").write_text("# FUM\n", encoding="utf-8")
        путь_реестра = корень / "реестр.json"
        путь_наблюдений = корень / "наблюдения.json"
        путь_схемы = корень / "схема.json"
        сам.записать_структуру(
            путь_реестра,
            реестр
            if реестр is not None
            else json.loads(КОРРЕКТНЫЙ_РЕЕСТР.read_text(encoding="utf-8")),
        )
        сам.записать_структуру(
            путь_наблюдений,
            наблюдения
            if наблюдения is not None
            else json.loads(НАБЛЮДЕНИЯ.read_text(encoding="utf-8")),
        )
        путь_схемы.write_bytes(СХЕМА.read_bytes())
        сам.выполнить_гит(корень, "add", "--", ".")
        сам.выполнить_гит(корень, "commit", "-m", "Создать фикстуру")
        return корень, путь_реестра, путь_схемы, путь_наблюдений

    def выбрать(
        сам,
        корень: Path,
        реестр: Path,
        схема: Path,
        наблюдения: Path,
    ) -> dict[str, object]:
        результат = сам.выполнить(
            корень,
            "выбрать",
            "--корень-рабочей-копии",
            str(корень),
            "--реестр",
            str(реестр),
            "--схема",
            str(схема),
            "--наблюдения",
            str(наблюдения),
            "--json",
        )
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        return json.loads(результат.stdout)

    def аргументы_выбора(
        сам,
        корень: Path,
        реестр: Path,
        схема: Path,
        наблюдения: Path,
        выбор: dict[str, object],
    ) -> list[str]:
        return [
            "--корень-рабочей-копии",
            str(корень),
            "--реестр",
            str(реестр),
            "--схема",
            str(схема),
            "--наблюдения",
            str(наблюдения),
            "--expected-job-id",
            str(выбор["job_id"]),
            "--expected-spec-generation",
            str(выбор["spec_generation"]),
            "--expected-registry-generation",
            str(выбор["поколение_реестра"]),
            "--expected-run-key",
            str(выбор["run_key"]),
        ]

    def test_выбор_следует_типизированному_сроку_приоритету_и_идентификатору_задания(
        сам,
    ) -> None:
        основа = json.loads(КОРРЕКТНЫЙ_РЕЕСТР.read_text(encoding="utf-8"))
        шаблон = основа["задания"][0]
        задания: list[dict[str, object]] = []
        for идентификатор, якорь, приоритет in (
            ("master.later", "2026-08-05T00:00:00Z", 0),
            ("master.earlier-z", "2026-08-05T00:01:00Z", 5),
            ("master.earlier-b", "2026-08-05T00:01:00Z", 3),
            ("master.earlier-a", "2026-08-05T00:01:00Z", 3),
        ):
            задание = deepcopy(шаблон)
            задание["job_id"] = идентификатор
            задание["приоритет"] = приоритет
            задание["триггер"]["якорь"] = якорь
            задание["курсор_результата"]["последнее_наступление"] = None
            задания.append(задание)
        основа["задания"] = list(reversed(задания))
        корень, реестр, схема, наблюдения = сам.создать_временный_репозиторий(
            основа
        )

        выбор = сам.выбрать(корень, реестр, схема, наблюдения)

        сам.assertEqual(выбор["состояние"], "выбрано")
        сам.assertEqual(выбор["число_готовых"], 4)
        сам.assertEqual(выбор["job_id"], "master.earlier-a")
        сам.assertEqual(
            выбор["trigger_occurrence"],
            {"момент": "2026-08-05T00:06:00Z", "тип": "расписание"},
        )
        сам.assertRegex(str(выбор["run_key"]), r"^sha256:[0-9a-f]{64}$")

        основа["задания"] = задания
        сам.записать_структуру(реестр, основа)
        повтор = сам.выбрать(корень, реестр, схема, наблюдения)
        сам.assertEqual(повтор, выбор)


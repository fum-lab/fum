    def test_параллельное_сравнение_и_замена_даёт_одного_победителя_и_точный_повтор(
        сам,
    ) -> None:
        основа = json.loads(КОРРЕКТНЫЙ_РЕЕСТР.read_text(encoding="utf-8"))
        основа["задания"] = [основа["задания"][0]]
        корень, реестр, схема, наблюдения = сам.создать_временный_репозиторий(
            основа
        )
        выбор = сам.выбрать(корень, реестр, схема, наблюдения)
        общие = сам.аргументы_выбора(
            корень,
            реестр,
            схема,
            наблюдения,
            выбор,
        )
        попытки = [str(uuid.uuid4()), str(uuid.uuid4())]
        процессы = [
            subprocess.Popen(
                [
                    sys.executable,
                    str(СЦЕНАРИЙ),
                    "зарезервировать",
                    *общие,
                    "--идентификатор-попытки",
                    попытка,
                    "--json",
                ],
                cwd=корень,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
            )
            for попытка in попытки
        ]
        ответы: list[tuple[int, dict[str, object]]] = []
        for процесс in процессы:
            вывод, ошибка = процесс.communicate(timeout=20)
            сам.assertIn(процесс.returncode, {0, 4}, ошибка)
            ответы.append((int(процесс.returncode), json.loads(вывод)))

        сам.assertEqual(sorted(код for код, _ in ответы), [0, 4])
        победитель = попытки[[код for код, _ in ответы].index(0)]
        повтор = сам.выполнить(
            корень,
            "зарезервировать",
            *общие,
            "--идентификатор-попытки",
            победитель,
            "--json",
        )
        сам.assertEqual(повтор.returncode, 0, повтор.stderr)
        сам.assertEqual(json.loads(повтор.stdout)["владение"], "существующее")

        сам.assertEqual(
            сам.выполнить_гит(корень, "status", "--porcelain").stdout,
            "",
        )


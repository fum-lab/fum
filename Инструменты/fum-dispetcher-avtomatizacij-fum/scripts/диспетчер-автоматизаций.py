def зарезервировать_запуск(
    корень_сырой: str,
    путь_реестра: str,
    путь_схемы: str,
    источник_наблюдений: str | dict[str, object],
    ожидаемое_задание: str,
    ожидаемое_поколение: int,
    ожидаемое_поколение_реестра: int,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
) -> tuple[int, dict[str, object]]:
    проверить_универсальный_идентификатор(
        идентификатор_попытки,
        "идентификатор_попытки",
    )
    if ШАБЛОН_КЛЮЧА_ЗАПУСКА.fullmatch(ожидаемый_ключ_запуска) is None:
        raise ОшибкаКонтракта("expected-run-key имеет неверный формат")
    корень, реестр, выбор, вершина, задание = подготовить_выбор_для_мутации(
        корень_сырой,
        путь_реестра,
        путь_схемы,
        источник_наблюдений,
        ожидаемое_задание,
        ожидаемое_поколение,
        ожидаемое_поколение_реестра,
        ожидаемый_ключ_запуска,
    )
    ветка = потребовать_строку(выбор["branch_ref"], "выбор.branch_ref")
    ссылка = ссылка_резервации(корень, ветка, ожидаемое_задание)
    новая_резервация = {
        "версия_схемы": 2,
        "branch_ref": ветка,
        "selection_head": вершина,
        "идентификатор_реестра": выбор["идентификатор_реестра"],
        "версия_схемы_реестра": выбор["версия_схемы_реестра"],
        "поколение_реестра": выбор["поколение_реестра"],
        "хэш_реестра": хэш_реестра(реестр),
        "job_id": выбор["job_id"],
        "spec_generation": выбор["spec_generation"],
        "trigger_occurrence": выбор["trigger_occurrence"],
        "run_key": выбор["run_key"],
        "идентификатор_попытки": идентификатор_попытки,
        "фаза": "зарезервирован",
        "исход": None,
        "идентификатор_созданной_задачи": None,
        "подтверждение_результата": None,
        "курсор_до": задание["курсор_результата"],
        "task_id": None,
        "generation": None,
    }
    новый_идентификатор_объекта = записать_объект_резервации(
        корень,
        новая_резервация,
        ветка,
        ожидаемое_задание,
    )
    for _ in range(МАКСИМУМ_ПОПЫТОК_СРАВНЕНИЯ_И_ЗАМЕНЫ):
        существующий, прежний_идентификатор_объекта = прочитать_резервацию(
            корень,
            ссылка,
            ветка,
            ожидаемое_задание,
        )
        if существующий is not None:
            та_же_попытка = (
                существующий["идентификатор_попытки"]
                == идентификатор_попытки
            )
            тот_же = тот_же_запуск(существующий, выбор, вершина, реестр)
            if та_же_попытка:
                if тот_же and существующий["фаза"] == "зарезервирован":
                    return 0, {
                        "состояние": "зарезервирован",
                        "владение": "существующее",
                        "branch_ref": ветка,
                        "job_id": ожидаемое_задание,
                        "run_key": ожидаемый_ключ_запуска,
                    }
                return ответ_занятой_резервации()
            допускает_замену = (
                существующий["фаза"] == "завершён"
                and существующий["исход"]
                == "безопасный_отказ_до_эффекта"
            ) or (
                существующий["фаза"] == "завершён"
                and существующий["исход"] == "успех"
                and существующий["run_key"] != ожидаемый_ключ_запуска
            )
            if not допускает_замену:
                return ответ_занятой_резервации()
        if заменить_резервацию_сравнением(
            корень,
            ссылка,
            прежний_идентификатор_объекта,
            новый_идентификатор_объекта,
            ветка,
            вершина,
        ):
            return 0, {
                "состояние": "зарезервирован",
                "владение": "новое",
                "branch_ref": ветка,
                "job_id": ожидаемое_задание,
                "run_key": ожидаемый_ключ_запуска,
            }
    raise ОшибкаКонтракта(
        "исчерпаны попытки сравнения и замены резервации"
    )


def заменить_резервацию_перед_вызовом_среды(
    корень: Path,
    ссылка_резервации_запуска: str,
    прежний_объект: str,
    новый_объект: str,
    ветка: str,
    вершина: str,
) -> bool:
    состояние, объект_управления, ссылка_управления_диспетчером = (
        снимок_состояния_управления(корень, ветка)
    )
    if состояние != "inactive":
        return False
    проверка_управления = команда_проверки_служебной_ссылки(
        ссылка_управления_диспетчером,
        объект_управления,
        len(вершина),
    )
    транзакция = (
        "start\n"
        f"verify {ветка} {вершина}\n"
        f"{проверка_управления}"
        f"update {ссылка_резервации_запуска} "
        f"{новый_объект} {прежний_объект}\n"
        "prepare\n"
        "commit\n"
    )
    результат = выполнить_гит(
        корень,
        "update-ref",
        "--no-deref",
        "--stdin",
        вход=транзакция,
    )
    if результат.returncode == 0:
        return True
    if вершина_ветки(корень, ветка) != вершина:
        return False
    if (
        прочитать_идентификатор_объекта_ссылки(
            корень,
            ссылка_резервации_запуска,
        )
        != прежний_объект
        or прочитать_идентификатор_объекта_ссылки(
            корень,
            ссылка_управления_диспетчером,
        )
        != объект_управления
    ):
        return False
    подробность = результат.stderr.strip() or "Git не вернул текст ошибки"
    raise ОшибкаКонтракта(
        f"не удалось атомарно проверить управляющий fence: {подробность}"
    )


def начать_вызов_среды(
    корень_сырой: str,
    путь_реестра: str,
    путь_схемы: str,
    источник_наблюдений: str | dict[str, object],
    ожидаемое_задание: str,
    ожидаемое_поколение: int,
    ожидаемое_поколение_реестра: int,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
) -> tuple[int, dict[str, object]]:
    проверить_универсальный_идентификатор(идентификатор_попытки, "идентификатор_попытки")
    корень, реестр, выбор, вершина, _ = подготовить_выбор_для_мутации(
        корень_сырой,
        путь_реестра,
        путь_схемы,
        источник_наблюдений,
        ожидаемое_задание,
        ожидаемое_поколение,
        ожидаемое_поколение_реестра,
        ожидаемый_ключ_запуска,
    )
    ветка = потребовать_строку(выбор["branch_ref"], "выбор.branch_ref")
    ссылка = ссылка_резервации(корень, ветка, ожидаемое_задание)
    for _ in range(МАКСИМУМ_ПОПЫТОК_СРАВНЕНИЯ_И_ЗАМЕНЫ):
        резервация, прежний_идентификатор_объекта = прочитать_резервацию(
            корень,
            ссылка,
            ветка,
            ожидаемое_задание,
        )
        if резервация is None or прежний_идентификатор_объекта is None:
            return ответ_занятой_резервации()
        if (
            резервация["идентификатор_попытки"] != идентификатор_попытки
            or not тот_же_запуск(резервация, выбор, вершина, реестр)
            or резервация["фаза"] != "зарезервирован"
        ):
            return ответ_занятой_резервации()
        новая_резервация = dict(резервация)
        новая_резервация["фаза"] = "вызов_мог_состояться"
        новый_идентификатор_объекта = записать_объект_резервации(
            корень,
            новая_резервация,
            ветка,
            ожидаемое_задание,
        )
        if заменить_резервацию_перед_вызовом_среды(
            корень,
            ссылка,
            прежний_идентификатор_объекта,
            новый_идентификатор_объекта,
            ветка,
            вершина,
        ):
            return 0, {
                "состояние": "вызов_разрешён",
                "job_id": ожидаемое_задание,
                "run_key": ожидаемый_ключ_запуска,
            }
        return ответ_занятой_резервации()
    raise ОшибкаКонтракта(
        "исчерпаны попытки сравнения и замены метки перед вызовом"
    )


def загрузить_точную_резервацию_после_вызова(
    корень_сырой: str,
    ожидаемая_ветка: str,
    ожидаемое_задание: str,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
    ожидаемая_вершина: str | None = None,
    ожидаемое_поколение: int | None = None,
    ожидаемое_поколение_реестра: int | None = None,
) -> tuple[Path, str, dict[str, object], str]:
    корень = проверить_корень_рабочей_копии(корень_сырой)
    проверить_ссылку_ветки(ожидаемая_ветка, "expected-branch-ref")
    потребовать_строку(ожидаемое_задание, "expected-job-id")
    if ШАБЛОН_КЛЮЧА_ЗАПУСКА.fullmatch(ожидаемый_ключ_запуска) is None:
        raise ОшибкаКонтракта("expected-run-key имеет неверный формат")
    проверить_универсальный_идентификатор(идентификатор_попытки, "идентификатор_попытки")
    ссылка = ссылка_резервации(корень, ожидаемая_ветка, ожидаемое_задание)
    резервация, идентификатор_объекта = прочитать_резервацию(
        корень,
        ссылка,
        ожидаемая_ветка,
        ожидаемое_задание,
    )
    if резервация is None or идентификатор_объекта is None:
        raise ОшибкаКонтракта("точная резервация отсутствует")
    if (
        резервация["run_key"] != ожидаемый_ключ_запуска
        or резервация["идентификатор_попытки"] != идентификатор_попытки
    ):
        raise ОшибкаКонтракта(
            "резервация принадлежит другой попытке или запуску"
        )
    if ожидаемая_вершина is not None and (
        ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(ожидаемая_вершина) is None
        or резервация["selection_head"] != ожидаемая_вершина
    ):
        raise ОшибкаКонтракта("ожидаемая вершина общего запуска изменилась")
    if ожидаемое_поколение is not None and (
        резервация["spec_generation"] != ожидаемое_поколение
    ):
        raise ОшибкаКонтракта("ожидаемое поколение задания изменилось")
    if ожидаемое_поколение_реестра is not None and (
        резервация["поколение_реестра"] != ожидаемое_поколение_реестра
    ):
        raise ОшибкаКонтракта("ожидаемое поколение реестра изменилось")
    return корень, ссылка, резервация, идентификатор_объекта


def подтвердить_создание(
    корень_сырой: str,
    ожидаемая_ветка: str,
    ожидаемое_задание: str,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
    идентификатор_созданной_задачи: str,
    ожидаемая_вершина: str | None = None,
    ожидаемое_поколение: int | None = None,
    ожидаемое_поколение_реестра: int | None = None,
) -> tuple[int, dict[str, object]]:
    потребовать_строку(
        идентификатор_созданной_задачи,
        "идентификатор_созданной_задачи",
    )
    for _ in range(МАКСИМУМ_ПОПЫТОК_СРАВНЕНИЯ_И_ЗАМЕНЫ):
        корень, ссылка, резервация, прежний_идентификатор_объекта = загрузить_точную_резервацию_после_вызова(
            корень_сырой,
            ожидаемая_ветка,
            ожидаемое_задание,
            ожидаемый_ключ_запуска,
            идентификатор_попытки,
            ожидаемая_вершина,
            ожидаемое_поколение,
            ожидаемое_поколение_реестра,
        )
        if резервация["фаза"] == "задача_создана":
            if (
                резервация["идентификатор_созданной_задачи"]
                == идентификатор_созданной_задачи
            ):
                return 0, {
                    "состояние": "создание_подтверждено",
                    "владение": "существующее",
                }
            return ответ_занятой_резервации()
        if резервация["фаза"] != "вызов_мог_состояться":
            return ответ_занятой_резервации()
        новая_резервация = dict(резервация)
        новая_резервация["фаза"] = "задача_создана"
        новая_резервация["идентификатор_созданной_задачи"] = (
            идентификатор_созданной_задачи
        )
        новый_идентификатор_объекта = записать_объект_резервации(
            корень,
            новая_резервация,
            ожидаемая_ветка,
            ожидаемое_задание,
        )
        if заменить_резервацию_сравнением(
            корень,
            ссылка,
            прежний_идентификатор_объекта,
            новый_идентификатор_объекта,
        ):
            return 0, {
                "состояние": "создание_подтверждено",
                "владение": "новое",
            }
    raise ОшибкаКонтракта(
        "исчерпаны попытки сравнения и замены подтверждения создания"
    )


def завершить_резервацию(
    корень_сырой: str,
    ожидаемая_ветка: str,
    ожидаемое_задание: str,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
    исход: str,
    подтверждение_результата: str | None,
) -> tuple[int, dict[str, object]]:
    if исход not in {"успех", "неопределённый"}:
        raise ОшибкаКонтракта("завершить поддерживает успех или неопределённый")
    if исход == "успех":
        потребовать_строку(
            подтверждение_результата,
            "подтверждение_результата",
        )
    elif подтверждение_результата is not None:
        raise ОшибкаКонтракта(
            "неопределённый исход не принимает подтверждение результата"
        )
    for _ in range(МАКСИМУМ_ПОПЫТОК_СРАВНЕНИЯ_И_ЗАМЕНЫ):
        корень, ссылка, резервация, прежний_идентификатор_объекта = загрузить_точную_резервацию_после_вызова(
            корень_сырой,
            ожидаемая_ветка,
            ожидаемое_задание,
            ожидаемый_ключ_запуска,
            идентификатор_попытки,
        )
        if резервация["фаза"] == "завершён":
            if (
                резервация["исход"] == исход
                and резервация["подтверждение_результата"]
                == подтверждение_результата
            ):
                return 0, {
                    "состояние": "завершён",
                    "исход": исход,
                    "владение": "существующее",
                }
            return ответ_занятой_резервации()
        допустимые_фазы = (
            {"задача_создана"}
            if исход == "успех"
            else {"вызов_мог_состояться", "задача_создана"}
        )
        if резервация["фаза"] not in допустимые_фазы:
            return ответ_занятой_резервации()
        новая_резервация = dict(резервация)
        новая_резервация["фаза"] = "завершён"
        новая_резервация["исход"] = исход
        новая_резервация["подтверждение_результата"] = подтверждение_результата
        новый_идентификатор_объекта = записать_объект_резервации(
            корень,
            новая_резервация,
            ожидаемая_ветка,
            ожидаемое_задание,
        )
        if заменить_резервацию_сравнением(
            корень,
            ссылка,
            прежний_идентификатор_объекта,
            новый_идентификатор_объекта,
        ):
            return 0, {
                "состояние": "завершён",
                "исход": исход,
                "владение": "новое",
            }
    raise ОшибкаКонтракта(
        "исчерпаны попытки сравнения и замены при завершении"
    )


def освободить_резервацию(
    корень_сырой: str,
    ожидаемая_ветка: str,
    ожидаемое_задание: str,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
) -> tuple[int, dict[str, object]]:
    for _ in range(МАКСИМУМ_ПОПЫТОК_СРАВНЕНИЯ_И_ЗАМЕНЫ):
        корень, ссылка, резервация, прежний_идентификатор_объекта = загрузить_точную_резервацию_после_вызова(
            корень_сырой,
            ожидаемая_ветка,
            ожидаемое_задание,
            ожидаемый_ключ_запуска,
            идентификатор_попытки,
        )
        if (
            резервация["фаза"] == "завершён"
            and резервация["исход"] == "безопасный_отказ_до_эффекта"
        ):
            return 0, {
                "состояние": "освобождён",
                "исход": "безопасный_отказ_до_эффекта",
                "владение": "существующее",
            }
        if резервация["фаза"] != "зарезервирован":
            return ответ_занятой_резервации()
        новая_резервация = dict(резервация)
        новая_резервация["фаза"] = "завершён"
        новая_резервация["исход"] = "безопасный_отказ_до_эффекта"
        новый_идентификатор_объекта = записать_объект_резервации(
            корень,
            новая_резервация,
            ожидаемая_ветка,
            ожидаемое_задание,
        )
        if заменить_резервацию_сравнением(
            корень,
            ссылка,
            прежний_идентификатор_объекта,
            новый_идентификатор_объекта,
        ):
            return 0, {
                "состояние": "освобождён",
                "исход": "безопасный_отказ_до_эффекта",
                "владение": "новое",
            }
    raise ОшибкаКонтракта(
        "исчерпаны попытки сравнения и замены при безопасном освобождении"
    )



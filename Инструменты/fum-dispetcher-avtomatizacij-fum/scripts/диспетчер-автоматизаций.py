def прочитать_наблюдения_команды(
    разобранные: argparse.Namespace,
) -> dict[str, object]:
    путь = getattr(разобранные, "наблюдения", None)
    текст = getattr(разобранные, "текст_наблюдений", None)
    if путь is not None:
        значение = прочитать_данные(путь, "наблюдения")
    else:
        if not isinstance(текст, str) or not текст:
            raise ОшибкаКонтракта("наблюдения JSON отсутствуют")
        try:
            значение = json.loads(
                текст,
                object_pairs_hook=собрать_объект_без_повторов,
                parse_constant=lambda константа: (_ for _ in ()).throw(
                    ОшибкаКонтракта(
                        f"наблюдения содержат неконечную константу {константа}"
                    )
                ),
            )
        except (UnicodeError, json.JSONDecodeError) as ошибка:
            raise ОшибкаКонтракта(
                "наблюдения не являются корректным JSON"
            ) from ошибка
    return проверить_наблюдения(значение)



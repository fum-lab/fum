def проверить_политику_ошибки(значение: object, путь: str) -> None:
    политика = потребовать_объект(значение, путь)
    проверить_поля(политика, ПОЛЯ_ПОЛИТИКИ_ОШИБКИ, путь)
    if политика["режим"] != "закрытый_отказ":
        raise ОшибкаКонтракта(f"{путь}.режим: поддерживается закрытый_отказ")
    if политика["повтор"] not in ПОВТОРЫ_ПОСЛЕ_ОШИБКИ:
        raise ОшибкаКонтракта(f"{путь}.повтор: неизвестная политика повтора")
    if политика["неоднозначный_результат"] not in НЕОДНОЗНАЧНЫЕ_РЕЗУЛЬТАТЫ:
        raise ОшибкаКонтракта(
            f"{путь}.неоднозначный_результат: неизвестная политика"
        )


def проверить_задание(
    значение: object,
    номер: int,
    реестр: dict[str, object],
) -> str:
    путь = f"реестр.задания[{номер}]"
    задание = потребовать_объект(значение, путь)
    проверить_поля(задание, ПОЛЯ_ЗАДАНИЯ, путь)
    идентификатор_задания = потребовать_строку(
        задание["job_id"],
        f"{путь}.job_id",
    )
    if not ШАБЛОН_ИДЕНТИФИКАТОРА.fullmatch(идентификатор_задания):
        raise ОшибкаКонтракта(f"{путь}.job_id: неверный устойчивый идентификатор")
    поколение = потребовать_целое(
        задание["поколение"],
        f"{путь}.поколение",
        1,
    )
    потребовать_целое(задание["приоритет"], f"{путь}.приоритет")
    проверить_тип_и_контракт(задание["адаптер"], f"{путь}.адаптер")

    цель = потребовать_объект(задание["цель"], f"{путь}.цель")
    проверить_поля(цель, ПОЛЯ_ЦЕЛИ, f"{путь}.цель")
    проверить_ссылку_ветки(цель["branch_ref"], f"{путь}.цель.branch_ref")
    проверить_путь_проекта(цель["путь_проекта"], f"{путь}.цель.путь_проекта")
    for поле in ПОЛЯ_ЦЕЛИ:
        if цель[поле] != реестр[поле]:
            raise ОшибкаКонтракта(
                f"{путь}.цель.{поле}: не совпадает с веточным реестром"
            )

    триггер = потребовать_объект(задание["триггер"], f"{путь}.триггер")
    тип_триггера = проверить_триггер(триггер, f"{путь}.триггер")
    проверить_условия(задание["условия_допуска"], f"{путь}.условия_допуска")

    состояние = потребовать_строку(задание["состояние"], f"{путь}.состояние")
    if состояние not in СОСТОЯНИЯ:
        raise ОшибкаКонтракта(f"{путь}.состояние: недопустимое состояние")

    класс_эффекта = проверить_эффект(задание["эффект"], f"{путь}.эффект")
    проверить_исполнителя(
        задание["исполнитель"],
        f"{путь}.исполнитель",
        класс_эффекта,
    )
    проверить_защиту(
        задание["защита_поколения"],
        f"{путь}.защита_поколения",
        поколение,
    )
    проверить_курсор(
        задание["курсор_результата"],
        f"{путь}.курсор_результата",
        тип_триггера,
        триггер,
    )
    проверить_политику_ошибки(
        задание["политика_ошибки"],
        f"{путь}.политика_ошибки",
    )
    return идентификатор_задания


def проверить_структуру_реестра(значение: object) -> dict[str, object]:
    реестр = потребовать_объект(значение, "реестр")
    проверить_поля(реестр, ПОЛЯ_РЕЕСТРА, "реестр")
    if реестр["версия_схемы"] != ВЕРСИЯ_СХЕМЫ:
        raise ОшибкаКонтракта(
            "реестр.версия_схемы: поддерживается только версия 1"
        )
    потребовать_строку(
        реестр["идентификатор_реестра"],
        "реестр.идентификатор_реестра",
    )
    потребовать_целое(
        реестр["поколение_реестра"],
        "реестр.поколение_реестра",
        1,
    )
    проверить_ссылку_ветки(реестр["branch_ref"], "реестр.branch_ref")
    потребовать_строку(
        реестр["идентификатор_проекта"],
        "реестр.идентификатор_проекта",
    )
    if реестр["якорь_рабочей_копии"] != ".":
        raise ОшибкаКонтракта(
            "реестр.якорь_рабочей_копии: версия 1 требует точный якорь ."
        )
    проверить_путь_проекта(
        реестр["путь_проекта"],
        "реестр.путь_проекта",
    )
    задания = потребовать_массив(реестр["задания"], "реестр.задания")
    идентификаторы: set[str] = set()
    for номер, задание in enumerate(задания):
        идентификатор_задания = проверить_задание(задание, номер, реестр)
        if идентификатор_задания in идентификаторы:
            raise ОшибкаКонтракта(
                f"реестр.задания: повтор job_id {идентификатор_задания}"
            )
        идентификаторы.add(идентификатор_задания)
    return реестр


def проверить_реестр(
    значение: object,
    корень: Path,
) -> dict[str, object]:
    реестр = проверить_структуру_реестра(значение)
    проверить_проект_в_рабочей_копии(реестр, корень)
    return реестр


def проверить_наблюдения(значение: object) -> dict[str, object]:
    наблюдения = потребовать_объект(значение, "наблюдения")
    проверить_поля(наблюдения, ПОЛЯ_НАБЛЮДЕНИЙ, "наблюдения")
    if наблюдения["версия_схемы"] != 1:
        raise ОшибкаКонтракта(
            "наблюдения.версия_схемы: поддерживается только версия 1"
        )
    разобрать_момент(наблюдения["момент"], "наблюдения.момент")
    условия = потребовать_объект(наблюдения["условия"], "наблюдения.условия")
    for имя, значение_условия in условия.items():
        потребовать_строку(имя, "наблюдения.условия.<имя>")
        if type(значение_условия) is not bool:
            raise ОшибкаКонтракта(
                f"наблюдения.условия.{имя}: ожидалось логическое значение"
            )
    события = потребовать_объект(
        наблюдения["подтверждённые_события"],
        "наблюдения.подтверждённые_события",
    )
    for имя, число in события.items():
        потребовать_строку(имя, "наблюдения.подтверждённые_события.<имя>")
        потребовать_целое(
            число,
            f"наблюдения.подтверждённые_события.{имя}",
        )
    return наблюдения


def вычислить_наступление(
    задание: dict[str, object],
    наблюдения: dict[str, object],
) -> str | None:
    триггер = потребовать_объект(задание["триггер"], "задание.триггер")
    курсор = потребовать_объект(
        задание["курсор_результата"],
        "задание.курсор_результата",
    )
    if триггер["тип"] == "расписание":
        момент = разобрать_момент(наблюдения["момент"], "наблюдения.момент")
        якорь = разобрать_момент(триггер["якорь"], "задание.триггер.якорь")
        if момент < якорь:
            return None
        интервал = триггер["интервал_секунды"]
        if type(интервал) is not int:
            raise ОшибкаКонтракта("внутренняя ошибка интервала")
        число_интервалов = int((момент - якорь).total_seconds()) // интервал
        наступление = якорь + timedelta(seconds=число_интервалов * интервал)
        последнее = курсор["последнее_наступление"]
        if последнее is not None:
            последний_момент = разобрать_момент(
                последнее,
                "задание.курсор_результата.последнее_наступление",
            )
            if наступление <= последний_момент:
                return None
        return представить_момент(наступление)

    тип_события = триггер["тип_события"]
    порог = курсор["следующий_порог"]
    каждые = триггер["каждые"]
    if (
        not isinstance(тип_события, str)
        or type(порог) is not int
        or type(каждые) is not int
    ):
        raise ОшибкаКонтракта("внутренняя ошибка порогового триггера")
    события = потребовать_объект(
        наблюдения["подтверждённые_события"],
        "наблюдения.подтверждённые_события",
    )
    число = события.get(тип_события, 0)
    if type(число) is not int or число < порог:
        return None
    начало = порог - каждые + 1
    return f"{тип_события}:{начало}-{порог}"


def вычислить_невыполненные_условия(
    задание: dict[str, object],
    наблюдения: dict[str, object],
) -> list[str]:
    значения = потребовать_объект(наблюдения["условия"], "наблюдения.условия")
    невыполненные: list[str] = []
    условия = потребовать_массив(
        задание["условия_допуска"],
        "задание.условия_допуска",
    )
    for сырое_условие in условия:
        условие = потребовать_объект(сырое_условие, "задание.условие")
        if значения.get(условие["наблюдение"]) is not условие["ожидается"]:
            идентификатор = условие["идентификатор"]
            if isinstance(идентификатор, str):
                невыполненные.append(идентификатор)
    return невыполненные


def моделировать_задание(
    задание: dict[str, object],
    наблюдения: dict[str, object],
) -> dict[str, object]:
    наступление = вычислить_наступление(задание, наблюдения)
    невыполненные = вычислить_невыполненные_условия(задание, наблюдения)
    состояние = задание["состояние"]
    триггер_наступил = наступление is not None
    условия_выполнены = not невыполненные
    состояние_разрешает = состояние == "active"
    готово = триггер_наступил and условия_выполнены and состояние_разрешает

    if состояние == "paused":
        статус = "приостановлено"
    elif состояние == "blocked":
        статус = "заблокировано"
    elif состояние == "retired":
        статус = "выведено_из_эксплуатации"
    elif not триггер_наступил:
        статус = "ожидание_триггера"
    elif not условия_выполнены:
        статус = "ожидание_условий"
    else:
        статус = "готово"

    return {
        "job_id": задание["job_id"],
        "поколение": задание["поколение"],
        "наступление": наступление,
        "триггер_наступил": триггер_наступил,
        "невыполненные_условия": невыполненные,
        "условия_выполнены": условия_выполнены,
        "состояние_разрешает": состояние_разрешает,
        "готово": готово,
        "статус": статус,
    }


def вычислить_типизированное_наступление(
    задание: dict[str, object],
    наблюдения: dict[str, object],
) -> dict[str, object] | None:
    наступление = вычислить_наступление(задание, наблюдения)
    if наступление is None:
        return None
    триггер = потребовать_объект(задание["триггер"], "задание.триггер")
    if триггер["тип"] == "расписание":
        return {"тип": "расписание", "момент": наступление}
    курсор = потребовать_объект(
        задание["курсор_результата"],
        "задание.курсор_результата",
    )
    начало = курсор["следующий_порог"]
    каждые = триггер["каждые"]
    if type(начало) is not int or type(каждые) is not int:
        raise ОшибкаКонтракта("внутренняя ошибка типизированного наступления")
    return {
        "тип": "порог_подтверждённых_событий",
        "тип_события": триггер["тип_события"],
        "начало": начало - каждые + 1,
        "конец": начало,
    }


def вычислить_ключ_запуска(
    идентификатор_задания: str,
    поколение: int,
    наступление: dict[str, object],
) -> str:
    вход = {
        "job_id": идентификатор_задания,
        "spec_generation": поколение,
        "trigger_occurrence": наступление,
    }
    байты = json.dumps(
        вход,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return "sha256:" + hashlib.sha256(байты).hexdigest()


def ключ_срока(
    задание: dict[str, object],
    наступление: dict[str, object],
) -> tuple[object, ...]:
    тип = наступление["тип"]
    if тип == "расписание":
        момент = наступление.get("момент")
        разобранный = разобрать_момент(момент, "trigger_occurrence.момент")
        собственный_срок: tuple[object, ...] = (
            разобранный.year,
            разобранный.month,
            разобранный.day,
            разобранный.hour,
            разобранный.minute,
            разобранный.second,
        )
        ранг_типа = 0
    else:
        тип_события = потребовать_строку(
            наступление.get("тип_события"),
            "trigger_occurrence.тип_события",
        )
        конец = потребовать_целое(
            наступление.get("конец"),
            "trigger_occurrence.конец",
            1,
        )
        собственный_срок = (тип_события, конец)
        ранг_типа = 1
    приоритет = потребовать_целое(
        задание["приоритет"],
        "задание.приоритет",
    )
    идентификатор = потребовать_строку(задание["job_id"], "задание.job_id")
    return (ранг_типа, собственный_срок, приоритет, идентификатор)


def вычислить_выбор(
    реестр: dict[str, object],
    наблюдения: dict[str, object],
) -> dict[str, object]:
    сырые_задания = потребовать_массив(реестр["задания"], "реестр.задания")
    готовые: list[tuple[tuple[object, ...], dict[str, object], dict[str, object]]] = []
    for сырое_задание in сырые_задания:
        задание = потребовать_объект(сырое_задание, "реестр.задание")
        модель = моделировать_задание(задание, наблюдения)
        if модель["готово"] is not True:
            continue
        наступление = вычислить_типизированное_наступление(
            задание,
            наблюдения,
        )
        if наступление is None:
            raise ОшибкаКонтракта("готовое задание не имеет наступления")
        готовые.append((ключ_срока(задание, наступление), задание, наступление))

    основа: dict[str, object] = {
        "состояние": "нет_готовых",
        "идентификатор_реестра": реестр["идентификатор_реестра"],
        "версия_схемы_реестра": реестр["версия_схемы"],
        "поколение_реестра": реестр["поколение_реестра"],
        "число_готовых": len(готовые),
    }
    if not готовые:
        return основа
    _, задание, наступление = min(готовые, key=lambda элемент: элемент[0])
    поколение = потребовать_целое(
        задание["поколение"],
        "задание.поколение",
        1,
    )
    идентификатор = потребовать_строку(задание["job_id"], "задание.job_id")
    основа.update(
        {
            "состояние": "выбрано",
            "branch_ref": реестр["branch_ref"],
            "job_id": идентификатор,
            "spec_generation": поколение,
            "адаптер": задание["адаптер"],
            "цель": задание["цель"],
            "эффект": задание["эффект"],
            "исполнитель": задание["исполнитель"],
            "trigger_occurrence": наступление,
            "run_key": вычислить_ключ_запуска(
                идентификатор,
                поколение,
                наступление,
            ),
        }
    )
    return основа


def хэш_реестра(реестр: dict[str, object]) -> str:
    байты = json.dumps(
        реестр,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return "sha256:" + hashlib.sha256(байты).hexdigest()


def найти_задание(
    реестр: dict[str, object],
    идентификатор: str,
) -> dict[str, object]:
    задания = потребовать_массив(реестр["задания"], "реестр.задания")
    найденные = [
        потребовать_объект(задание, "реестр.задание")
        for задание in задания
        if isinstance(задание, dict) and задание.get("job_id") == идентификатор
    ]
    if len(найденные) != 1:
        raise ОшибкаКонтракта("ожидаемое задание отсутствует в реестре")
    return найденные[0]


def проверить_криптографический_хэш(значение: object, путь: str) -> str:
    строка = потребовать_строку(значение, путь)
    if ШАБЛОН_КЛЮЧА_ЗАПУСКА.fullmatch(строка) is None:
        raise ОшибкаКонтракта(f"{путь}: ожидался хэш SHA-256")
    return строка


def хэш_канонического_значения(значение: object) -> str:
    байты = json.dumps(
        значение,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return "sha256:" + hashlib.sha256(байты).hexdigest()


def публичное_состояние_заданий(
    реестр: dict[str, object],
    состояния_резерваций: dict[str, dict[str, object]] | None = None,
) -> dict[str, object]:
    """Вернуть канонический обезличенный снимок реестра и блокировок."""
    проверенный = проверить_структуру_реестра(реестр)
    резервации = состояния_резерваций or {}
    задания = потребовать_массив(проверенный["задания"], "реестр.задания")
    публичные: list[dict[str, object]] = []
    for сырое_задание in sorted(
        задания,
        key=lambda значение: str(
            потребовать_объект(значение, "реестр.задание")["job_id"]
        ),
    ):
        задание = потребовать_объект(сырое_задание, "реестр.задание")
        идентификатор = str(задание["job_id"])
        сырая_резервация = резервации.get(идентификатор)
        if сырая_резервация is None:
            блокировка: dict[str, object] = {"состояние": "отсутствует"}
        else:
            резервация = потребовать_объект(
                сырая_резервация,
                f"состояния_резерваций.{идентификатор}",
            )
            состояние = резервация.get("состояние", "существует")
            if состояние not in {"существует", "отсутствует"}:
                состояние = "неопределённо"
            блокировка = {"состояние": состояние}
            if состояние == "существует":
                фаза = резервация.get("фаза")
                исход = резервация.get("исход")
                блокировка.update({"фаза": фаза, "исход": исход})
        публичные.append(
            {
                "job_id": идентификатор,
                "поколение": deepcopy(задание["поколение"]),
                "адаптер": deepcopy(задание["адаптер"]),
                "триггер": deepcopy(задание["триггер"]),
                "условия_допуска": deepcopy(задание["условия_допуска"]),
                "состояние": deepcopy(задание["состояние"]),
                "эффект": deepcopy(задание["эффект"]),
                "курсор_результата": deepcopy(задание["курсор_результата"]),
                "блокировка": блокировка,
            }
        )
    return {
        "состояние": "корректен",
        "идентификатор_реестра": deepcopy(
            проверенный["идентификатор_реестра"]
        ),
        "поколение_реестра": deepcopy(проверенный["поколение_реестра"]),
        "branch_ref": deepcopy(проверенный["branch_ref"]),
        "задания": публичные,
    }


def потребовать_точные_поля_данных(
    данные: object,
    поля: set[str] | frozenset[str],
    намерение: str,
) -> dict[str, object]:
    объект = потребовать_объект(данные, f"данные.{намерение}")
    if set(объект) != set(поля):
        raise ОшибкаКонтракта(
            f"данные.{намерение}: неверный закрытый набор полей"
        )
    return объект


def изменение_управления(
    путь: str,
    старое: object,
    новое: object,
) -> dict[str, object]:
    return {
        "путь": путь,
        "старое": deepcopy(старое),
        "новое": deepcopy(новое),
    }


def путь_указателя(*компоненты: str) -> str:
    разделитель = chr(47)
    тильда = chr(126)
    экранированные = [
        компонент.replace(тильда, тильда + "0").replace(
            разделитель,
            тильда + "1",
        )
        for компонент in компоненты
    ]
    return разделитель + разделитель.join(экранированные)


def курсор_содержит_подтверждённый_результат(курсор: object) -> bool:
    объект = потребовать_объект(курсор, "курсор_результата")
    if объект.get("тип") == "расписание":
        return объект.get("последнее_наступление") is not None
    return bool(
        объект.get("последнее_число_подтверждённых_событий")
        or объект.get("последний_идентификатор_события")
    )


def идентификатор_предложения(
    предложение_без_идентификатора: dict[str, object],
) -> str:
    return хэш_канонического_значения(предложение_без_идентификатора)


def сформировать_предложение(
    реестр: dict[str, object],
    намерение: str,
    данные: dict[str, object],
    идентификатор_сообщения: str,
    хэш_сообщения: str,
    ожидаемая_вершина: str,
) -> dict[str, object]:
    """Преобразовать закрытое намерение в детерминированное предложение."""
    проверенный = проверить_структуру_реестра(реестр)
    точное_намерение = потребовать_строку(намерение, "намерение")
    if точное_намерение not in НАМЕРЕНИЯ_УПРАВЛЕНИЯ:
        допустимые = ", ".join(sorted(НАМЕРЕНИЯ_УПРАВЛЕНИЯ))
        raise ОшибкаКонтракта(
            f"неизвестное намерение; допустимы: {допустимые}"
        )
    потребовать_строку(идентификатор_сообщения, "идентификатор_сообщения")
    проверить_криптографический_хэш(хэш_сообщения, "хэш_сообщения")
    if ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(ожидаемая_вершина) is None:
        raise ОшибкаКонтракта("ожидаемая_вершина имеет неверный формат")

    до = deepcopy(проверенный)
    после = deepcopy(проверенный)
    изменения: list[dict[str, object]] = []
    подтверждения = ["применить"]
    последствия = ["существующая_резервация_не_отменяется"]
    идентификатор_задания: str | None = None
    поколение_задания_до: int | None = None
    поколение_задания_после: int | None = None
    эффект_задания: object = None
    нормализованные_данные = deepcopy(данные)

    if точное_намерение in НАМЕРЕНИЯ_УПРАВЛЕНИЯ_СРЕДОЙ:
        объект_данных = потребовать_точные_поля_данных(
            данные,
            {"текущий_статус"},
            точное_намерение,
        )
        старое, новое = (
            ("ACTIVE", "PAUSED")
            if точное_намерение == "приостановить_heartbeat"
            else ("PAUSED", "ACTIVE")
        )
        текущий_статус = потребовать_строку(
            объект_данных["текущий_статус"],
            "данные.текущий_статус",
        )
        if текущий_статус != старое:
            raise ОшибкаКонтракта(
                "наблюдённый host-статус не допускает это намерение"
            )
        изменения.append(
            изменение_управления(
                путь_указателя("host", "status"),
                старое,
                новое,
            )
        )
        область = "host_runtime"
        класс_эффекта = "изменение_host_runtime"
        последствия = [
            "уже_начатый_тик_не_отменяется",
            "возобновление_не_форсирует_тик",
        ]
    elif точное_намерение == "добавить_задание":
        объект_данных = потребовать_точные_поля_данных(
            данные,
            {"задание"},
            точное_намерение,
        )
        новое_задание = deepcopy(
            потребовать_объект(объект_данных["задание"], "данные.задание")
        )
        идентификатор_задания = потребовать_строку(
            новое_задание.get("job_id"),
            "данные.задание.job_id",
        )
        if any(
            isinstance(задание, dict)
            and задание.get("job_id") == идентификатор_задания
            for задание in потребовать_массив(до["задания"], "реестр.задания")
        ):
            raise ОшибкаКонтракта("добавляемый job_id уже существует")
        новое_задание["состояние"] = "blocked"
        новое_задание["поколение"] = 1
        защита = потребовать_объект(
            новое_задание.get("защита_поколения"),
            "данные.задание.защита_поколения",
        )
        защита["поколение"] = 1
        потребовать_массив(после["задания"], "реестр.задания").append(
            новое_задание
        )
        поколение_задания_после = 1
        эффект_задания = deepcopy(новое_задание.get("эффект"))
        изменения.append(
            изменение_управления(
                путь_указателя("задания", идентификатор_задания),
                None,
                новое_задание,
            )
        )
        if isinstance(эффект_задания, dict) and (
            эффект_задания.get("класс") == "внешний_эффект"
        ):
            подтверждения.append("разрешить_внешний_эффект")
        область = "реестр"
        класс_эффекта = "изменение_репозитория"
    else:
        допустимые_поля = {
            "изменить_триггер": {
                "job_id",
                "триггер",
                "курсор_результата",
            },
            "заменить_условия": {"job_id", "условия_допуска"},
            "снять_блокировку": {"job_id", "новое_состояние"},
        }.get(точное_намерение, {"job_id"})
        объект_данных = потребовать_точные_поля_данных(
            данные,
            допустимые_поля,
            точное_намерение,
        )
        идентификатор_задания = потребовать_строку(
            объект_данных["job_id"],
            "данные.job_id",
        )
        старое_задание = найти_задание(до, идентификатор_задания)
        новое_задание = найти_задание(после, идентификатор_задания)
        поколение_задания_до = потребовать_целое(
            старое_задание["поколение"],
            "задание.поколение",
            1,
        )
        поколение_задания_после = поколение_задания_до + 1
        эффект_задания = deepcopy(старое_задание["эффект"])
        путь_задания = путь_указателя("задания", идентификатор_задания)

        if точное_намерение == "изменить_триггер":
            новый_триггер = deepcopy(объект_данных["триггер"])
            новый_курсор = deepcopy(объект_данных["курсор_результата"])
            изменения.extend(
                [
                    изменение_управления(
                        f"{путь_задания}/триггер",
                        старое_задание["триггер"],
                        новый_триггер,
                    ),
                    изменение_управления(
                        f"{путь_задания}/курсор_результата",
                        старое_задание["курсор_результата"],
                        новый_курсор,
                    ),
                ]
            )
            if (
                старое_задание["курсор_результата"] != новый_курсор
                and (
                    курсор_содержит_подтверждённый_результат(
                        старое_задание["курсор_результата"]
                    )
                    or курсор_содержит_подтверждённый_результат(
                        новый_курсор
                    )
                )
            ):
                подтверждения.append("изменить_подтверждённый_курсор")
            if (
                старое_задание["триггер"] == новый_триггер
                and старое_задание["курсор_результата"] == новый_курсор
            ):
                raise ОшибкаКонтракта("изменение триггера не меняет задание")
            новое_задание["триггер"] = новый_триггер
            новое_задание["курсор_результата"] = новый_курсор
        elif точное_намерение == "заменить_условия":
            новые_условия = deepcopy(объект_данных["условия_допуска"])
            if старое_задание["условия_допуска"] == новые_условия:
                raise ОшибкаКонтракта("замена условий не меняет задание")
            изменения.append(
                изменение_управления(
                    f"{путь_задания}/условия_допуска",
                    старое_задание["условия_допуска"],
                    новые_условия,
                )
            )
            новое_задание["условия_допуска"] = новые_условия
        else:
            старое_состояние = потребовать_строку(
                старое_задание["состояние"],
                "задание.состояние",
            )
            if точное_намерение == "приостановить_задание":
                if старое_состояние != "active":
                    raise ОшибкаКонтракта("приостановить можно только active")
                новое_состояние = "paused"
            elif точное_намерение == "возобновить_задание":
                if старое_состояние != "paused":
                    raise ОшибкаКонтракта("возобновить можно только paused")
                новое_состояние = "active"
            elif точное_намерение == "заблокировать_задание":
                if старое_состояние not in {"active", "paused"}:
                    raise ОшибкаКонтракта(
                        "заблокировать можно только active или paused"
                    )
                новое_состояние = "blocked"
            elif точное_намерение == "снять_блокировку":
                if старое_состояние != "blocked":
                    raise ОшибкаКонтракта("задание не заблокировано")
                новое_состояние = потребовать_строку(
                    объект_данных["новое_состояние"],
                    "данные.новое_состояние",
                )
                if новое_состояние not in {"active", "paused"}:
                    raise ОшибкаКонтракта(
                        "снятие блокировки допускает active или paused"
                    )
                подтверждения.append("снять_safety_блокировку")
            else:
                if старое_состояние == "retired":
                    raise ОшибкаКонтракта("retired является терминальным")
                новое_состояние = "retired"
            изменения.append(
                изменение_управления(
                    f"{путь_задания}/состояние",
                    старое_состояние,
                    новое_состояние,
                )
            )
            новое_задание["состояние"] = новое_состояние

        if (
            isinstance(эффект_задания, dict)
            and эффект_задания.get("класс") == "внешний_эффект"
            and точное_намерение
            in {
                "возобновить_задание",
                "снять_блокировку",
                "изменить_триггер",
                "заменить_условия",
            }
            and "разрешить_внешний_эффект" not in подтверждения
        ):
            подтверждения.append("разрешить_внешний_эффект")

        новое_задание["поколение"] = поколение_задания_после
        новая_защита = потребовать_объект(
            новое_задание["защита_поколения"],
            "задание.защита_поколения",
        )
        старая_защита = потребовать_объект(
            старое_задание["защита_поколения"],
            "задание.защита_поколения",
        )
        новая_защита["поколение"] = поколение_задания_после
        изменения.extend(
            [
                изменение_управления(
                    f"{путь_задания}/поколение",
                    поколение_задания_до,
                    поколение_задания_после,
                ),
                изменение_управления(
                    f"{путь_задания}/защита_поколения/поколение",
                    старая_защита["поколение"],
                    поколение_задания_после,
                ),
            ]
        )
        область = "реестр"
        класс_эффекта = "изменение_репозитория"

    поколение_до = потребовать_целое(
        до["поколение_реестра"],
        "реестр.поколение_реестра",
        1,
    )
    if область == "реестр":
        после["поколение_реестра"] = поколение_до + 1
        изменения.append(
            изменение_управления(
                путь_указателя("поколение_реестра"),
                поколение_до,
                поколение_до + 1,
            )
        )
        проверить_структуру_реестра(после)
    else:
        проверить_структуру_реестра(после)

    тело: dict[str, object] = {
        "схема": СХЕМА_ПРЕДЛОЖЕНИЯ_УПРАВЛЕНИЯ,
        "идентификатор_сообщения": идентификатор_сообщения,
        "хэш_сообщения": хэш_сообщения,
        "намерение": точное_намерение,
        "область": область,
        "ожидаемая_вершина": ожидаемая_вершина,
        "ожидаемый_хэш_реестра": хэш_реестра(до),
        "ожидаемое_поколение_реестра": поколение_до,
        "новый_хэш_реестра": хэш_реестра(после),
        "новое_поколение_реестра": после["поколение_реестра"],
        "job_id": идентификатор_задания,
        "ожидаемое_поколение_задания": поколение_задания_до,
        "новое_поколение_задания": поколение_задания_после,
        "изменения": изменения,
        "класс_эффекта": класс_эффекта,
        "эффект_задания": эффект_задания,
        "последствия": последствия,
        "требуемые_подтверждения": подтверждения,
        "данные": нормализованные_данные,
        "реестр_после": после,
    }
    предложение = {
        "идентификатор_предложения": идентификатор_предложения(тело),
        **тело,
    }
    return проверить_предложение(предложение)


def проверить_предложение(значение: object) -> dict[str, object]:
    предложение = потребовать_объект(значение, "предложение")
    проверить_поля(
        предложение,
        ПОЛЯ_ПРЕДЛОЖЕНИЯ_УПРАВЛЕНИЯ,
        "предложение",
    )
    if предложение["схема"] != СХЕМА_ПРЕДЛОЖЕНИЯ_УПРАВЛЕНИЯ:
        raise ОшибкаКонтракта("предложение имеет неизвестную схему")
    точное_намерение = потребовать_строку(
        предложение["намерение"],
        "предложение.намерение",
    )
    if точное_намерение not in НАМЕРЕНИЯ_УПРАВЛЕНИЯ:
        raise ОшибкаКонтракта("предложение имеет неизвестное намерение")
    ожидаемая_область = (
        "host_runtime"
        if точное_намерение in НАМЕРЕНИЯ_УПРАВЛЕНИЯ_СРЕДОЙ
        else "реестр"
    )
    ожидаемый_класс = (
        "изменение_host_runtime"
        if ожидаемая_область == "host_runtime"
        else "изменение_репозитория"
    )
    if (
        предложение["область"] != ожидаемая_область
        or предложение["класс_эффекта"] != ожидаемый_класс
    ):
        raise ОшибкаКонтракта("предложение противоречит области эффекта")
    потребовать_строку(
        предложение["идентификатор_сообщения"],
        "предложение.идентификатор_сообщения",
    )
    проверить_криптографический_хэш(
        предложение["хэш_сообщения"],
        "предложение.хэш_сообщения",
    )
    for поле in (
        "идентификатор_предложения",
        "ожидаемый_хэш_реестра",
        "новый_хэш_реестра",
    ):
        проверить_криптографический_хэш(
            предложение[поле],
            f"предложение.{поле}",
        )
    вершина = предложение["ожидаемая_вершина"]
    if (
        not isinstance(вершина, str)
        or ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(вершина) is None
    ):
        raise ОшибкаКонтракта("предложение содержит неверную вершину")
    for поле in (
        "ожидаемое_поколение_реестра",
        "новое_поколение_реестра",
    ):
        потребовать_целое(предложение[поле], f"предложение.{поле}", 1)
    for поле in (
        "ожидаемое_поколение_задания",
        "новое_поколение_задания",
    ):
        значение_поколения = предложение[поле]
        if значение_поколения is not None:
            потребовать_целое(
                значение_поколения,
                f"предложение.{поле}",
                1,
            )
    изменения = потребовать_массив(
        предложение["изменения"],
        "предложение.изменения",
    )
    for номер, сырое_изменение in enumerate(изменения):
        изменение = потребовать_объект(
            сырое_изменение,
            f"предложение.изменения[{номер}]",
        )
        проверить_поля(
            изменение,
            ПОЛЯ_ИЗМЕНЕНИЯ_УПРАВЛЕНИЯ,
            f"предложение.изменения[{номер}]",
        )
        путь = потребовать_строку(
            изменение["путь"],
            f"предложение.изменения[{номер}].путь",
        )
        if not путь.startswith("/") or ".." in путь:
            raise ОшибкаКонтракта("предложение содержит небезопасный путь diff")
    подтверждения = потребовать_массив(
        предложение["требуемые_подтверждения"],
        "предложение.требуемые_подтверждения",
    )
    if (
        not подтверждения
        or "применить" not in подтверждения
        or len(подтверждения) != len(set(подтверждения))
        or any(значение not in ПОДТВЕРЖДЕНИЯ_УПРАВЛЕНИЯ for значение in подтверждения)
    ):
        raise ОшибкаКонтракта("предложение содержит неверные подтверждения")
    последствия = потребовать_массив(
        предложение["последствия"],
        "предложение.последствия",
    )
    for номер, последствие in enumerate(последствия):
        потребовать_строку(
            последствие,
            f"предложение.последствия[{номер}]",
        )
    реестр_после = проверить_структуру_реестра(
        предложение["реестр_после"]
    )
    if предложение["новый_хэш_реестра"] != хэш_реестра(реестр_после):
        raise ОшибкаКонтракта("предложение не совпадает с новым хэшем реестра")
    if (
        предложение["новое_поколение_реестра"]
        != реестр_после["поколение_реестра"]
    ):
        raise ОшибкаКонтракта("предложение не совпадает с новым поколением")
    данные = потребовать_объект(
        предложение["данные"],
        "предложение.данные",
    )
    if ожидаемая_область == "host_runtime":
        объект_данных_среды = потребовать_точные_поля_данных(
            данные,
            {"текущий_статус"},
            точное_намерение,
        )
        ожидаемый_старый_статус = (
            "ACTIVE"
            if точное_намерение == "приостановить_heartbeat"
            else "PAUSED"
        )
        if объект_данных_среды["текущий_статус"] != ожидаемый_старый_статус:
            raise ОшибкаКонтракта(
                "host-предложение не совпадает с исходным статусом"
            )
        if (
            предложение["job_id"] is not None
            or предложение["ожидаемое_поколение_задания"] is not None
            or предложение["новое_поколение_задания"] is not None
            or предложение["эффект_задания"] is not None
            or предложение["новое_поколение_реестра"]
            != предложение["ожидаемое_поколение_реестра"]
            or предложение["новый_хэш_реестра"]
            != предложение["ожидаемый_хэш_реестра"]
        ):
            raise ОшибкаКонтракта("host-предложение меняет реестр")
    else:
        if (
            предложение["новое_поколение_реестра"]
            != предложение["ожидаемое_поколение_реестра"] + 1
        ):
            raise ОшибкаКонтракта(
                "репозиторное предложение неверно повышает поколение"
            )
        if точное_намерение == "добавить_задание":
            потребовать_точные_поля_данных(
                данные,
                {"задание"},
                точное_намерение,
            )
        elif точное_намерение == "изменить_триггер":
            потребовать_точные_поля_данных(
                данные,
                {"job_id", "триггер", "курсор_результата"},
                точное_намерение,
            )
        elif точное_намерение == "заменить_условия":
            потребовать_точные_поля_данных(
                данные,
                {"job_id", "условия_допуска"},
                точное_намерение,
            )
        elif точное_намерение == "снять_блокировку":
            потребовать_точные_поля_данных(
                данные,
                {"job_id", "новое_состояние"},
                точное_намерение,
            )
        else:
            потребовать_точные_поля_данных(
                данные,
                {"job_id"},
                точное_намерение,
            )
        идентификатор_задания = потребовать_строку(
            предложение["job_id"],
            "предложение.job_id",
        )
        if точное_намерение != "добавить_задание" and (
            данные.get("job_id") != идентификатор_задания
        ):
            raise ОшибкаКонтракта("предложение подменяет job_id")
        задание_после = найти_задание(
            реестр_после,
            идентификатор_задания,
        )
        if (
            задание_после["поколение"]
            != предложение["новое_поколение_задания"]
        ):
            raise ОшибкаКонтракта(
                "предложение не совпадает с поколением задания"
            )
    тело = dict(предложение)
    заявленный_идентификатор = тело.pop("идентификатор_предложения")
    if заявленный_идентификатор != идентификатор_предложения(тело):
        raise ОшибкаКонтракта("дайджест предложения не совпадает")
    return предложение


def применить_предложение_к_реестру(
    реестр: dict[str, object],
    предложение: dict[str, object],
    подтверждения: set[str],
) -> tuple[str, dict[str, object]]:
    текущий = deepcopy(проверить_структуру_реестра(реестр))
    if set(предложение) == {
        "схема",
        "идентификатор_предложения",
        "состояние",
    } and предложение.get("схема") == СХЕМА_ОТМЕНЫ_ПРЕДЛОЖЕНИЯ:
        проверить_криптографический_хэш(
            предложение["идентификатор_предложения"],
            "отмена.идентификатор_предложения",
        )
        if предложение.get("состояние") != "отменено":
            raise ОшибкаКонтракта("отмена имеет неверное состояние")
        return "отменено", текущий
    проверенное = проверить_предложение(предложение)
    if (
        проверенное["область"] != "host_runtime"
        and хэш_реестра(текущий) == проверенное["новый_хэш_реестра"]
    ):
        return "уже_применено", текущий
    if (
        текущий["поколение_реестра"]
        != проверенное["ожидаемое_поколение_реестра"]
        or хэш_реестра(текущий)
        != проверенное["ожидаемый_хэш_реестра"]
    ):
        return "конфликт_поколения", текущий
    точные_подтверждения = {
        потребовать_строку(подтверждение, "подтверждение")
        for подтверждение in подтверждения
    }
    требуемые = set(
        потребовать_массив(
            проверенное["требуемые_подтверждения"],
            "предложение.требуемые_подтверждения",
        )
    )
    if not требуемые.issubset(точные_подтверждения):
        return "требуется_подтверждение", текущий
    воспроизведённое = сформировать_предложение(
        текущий,
        str(проверенное["намерение"]),
        deepcopy(
            потребовать_объект(
                проверенное["данные"],
                "предложение.данные",
            )
        ),
        str(проверенное["идентификатор_сообщения"]),
        str(проверенное["хэш_сообщения"]),
        str(проверенное["ожидаемая_вершина"]),
    )
    if воспроизведённое != проверенное:
        raise ОшибкаКонтракта("предложение не воспроизводится из основания")
    if проверенное["область"] == "host_runtime":
        return "требуется_изменение_host", текущий
    результат = deepcopy(
        потребовать_объект(
            проверенное["реестр_после"],
            "предложение.реестр_после",
        )
    )
    проверить_структуру_реестра(результат)
    return "применено", результат


def отменить_предложение(
    предложение: dict[str, object],
) -> dict[str, object]:
    if set(предложение) == {
        "схема",
        "идентификатор_предложения",
        "состояние",
    } and предложение.get("схема") == СХЕМА_ОТМЕНЫ_ПРЕДЛОЖЕНИЯ:
        проверить_криптографический_хэш(
            предложение["идентификатор_предложения"],
            "отмена.идентификатор_предложения",
        )
        if предложение.get("состояние") != "отменено":
            raise ОшибкаКонтракта("отмена имеет неверное состояние")
        return deepcopy(предложение)
    проверенное = проверить_предложение(предложение)
    return {
        "схема": СХЕМА_ОТМЕНЫ_ПРЕДЛОЖЕНИЯ,
        "идентификатор_предложения": проверенное[
            "идентификатор_предложения"
        ],
        "состояние": "отменено",
    }


def смоделировать(
    реестр: dict[str, object],
    наблюдения: dict[str, object],
) -> dict[str, object]:
    задания = потребовать_массив(реестр["задания"], "реестр.задания")
    упорядоченные = sorted(
        (потребовать_объект(задание, "реестр.задание") for задание in задания),
        key=lambda задание: (задание["приоритет"], задание["job_id"]),
    )
    return {
        "идентификатор_реестра": реестр["идентификатор_реестра"],
        "поколение_реестра": реестр["поколение_реестра"],
        "состояние": "смоделирован",
        "задания": [
            моделировать_задание(задание, наблюдения)
            for задание in упорядоченные
        ],
    }


def чистая_среда_гит() -> dict[str, str]:
    среда = {
        ключ: значение
        for ключ, значение in os.environ.items()
        if not ключ.upper().startswith("GIT_")
    }
    среда["GIT_NO_REPLACE_OBJECTS"] = "1"
    среда["GIT_OPTIONAL_LOCKS"] = "0"
    return среда


def выполнить_гит(
    корень: Path,
    *аргументы: str,
    вход: str | None = None,
) -> subprocess.CompletedProcess[str]:
    return выполнить_гит_процесс(
        корень,
        *аргументы,
        вход=вход,
        байтовый_режим=False,
    )


def выполнить_гит_байты(
    корень: Path,
    *аргументы: str,
    вход: bytes | None = None,
) -> subprocess.CompletedProcess[bytes]:
    return выполнить_гит_процесс(
        корень,
        *аргументы,
        вход=вход,
        байтовый_режим=True,
    )


def выполнить_гит_процесс(
    корень: Path,
    *аргументы: str,
    вход: str | bytes | None,
    байтовый_режим: bool,
) -> subprocess.CompletedProcess:
    параметры_текста: dict[str, object] = {}
    if not байтовый_режим:
        параметры_текста = {"encoding": "utf-8", "errors": "strict"}
    return subprocess.run(
        ["git", "--no-replace-objects", "-C", str(корень), *аргументы],
        check=False,
        capture_output=True,
        env=чистая_среда_гит(),
        input=вход,
        timeout=ТАЙМ_АУТ_ГИТ_СЕКУНДЫ,
        **параметры_текста,
    )


def выполнить_гит_строго(
    корень: Path,
    действие: str,
    *аргументы: str,
    вход: str | None = None,
) -> subprocess.CompletedProcess[str]:
    результат = выполнить_гит(корень, *аргументы, вход=вход)
    if результат.returncode != 0:
        подробность = результат.stderr.strip() or "Git не вернул текст ошибки"
        raise ОшибкаКонтракта(f"Не удалось {действие}: {подробность}")
    return результат


def идентичность_рабочей_копии(корень: Path) -> str:
    результат = выполнить_гит_строго(
        корень,
        "определить физический Git-каталог рабочей копии",
        "rev-parse",
        "--absolute-git-dir",
    )
    каталог = Path(результат.stdout.strip()).resolve()
    нормализованный = os.path.normcase(str(каталог))
    return hashlib.sha256(нормализованный.encode("utf-8")).hexdigest()


def вершина_ветки(корень: Path, ссылка: str) -> str:
    результат = выполнить_гит_строго(
        корень,
        f"прочитать вершину {ссылка}",
        "rev-parse",
        "--verify",
        f"{ссылка}^{{commit}}",
    )
    вершина = результат.stdout.strip()
    if ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(вершина) is None:
        raise ОшибкаКонтракта(
            "Git вернул неверный идентификатор объекта вершины ветки"
        )
    return вершина


def проверить_авторитетный_реестр(
    корень: Path,
    путь: str | Path,
    ссылка: str,
    ожидаемый_реестр: dict[str, object],
) -> str:
    активная = выполнить_гит_строго(
        корень,
        "проверить активную именованную ветку",
        "symbolic-ref",
        "--quiet",
        "HEAD",
    ).stdout.strip()
    if активная != ссылка:
        raise ОшибкаКонтракта("реестр относится не к активной именованной ветке")
    файл = Path(путь)
    try:
        разрешённый = файл.resolve(strict=True)
        относительный = разрешённый.relative_to(корень)
    except (OSError, ValueError) as ошибка:
        raise ОшибкаКонтракта(
            "мутирующая команда требует реестр внутри рабочей копии"
        ) from ошибка
    кандидат = корень
    for часть in относительный.parts:
        кандидат = кандидат / часть
        if кандидат.is_symlink():
            raise ОшибкаКонтракта("путь реестра содержит символическую ссылку")
    вершина = вершина_ветки(корень, ссылка)
    снимок = выполнить_гит_строго(
        корень,
        "прочитать реестр из точной вершины ветки",
        "show",
        f"{вершина}:{относительный.as_posix()}",
    ).stdout
    try:
        текущий = разрешённый.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as ошибка:
        raise ОшибкаКонтракта("не удалось прочитать реестр") from ошибка
    if текущий != снимок:
        raise ОшибкаКонтракта(
            "реестр рабочей копии не совпадает с точной вершиной ветки"
        )
    try:
        проверенный_реестр = json.loads(
            снимок,
            object_pairs_hook=собрать_объект_без_повторов,
        )
    except (ОшибкаКонтракта, json.JSONDecodeError) as ошибка:
        raise ОшибкаКонтракта(
            "реестр из точной вершины ветки содержит неверный JSON"
        ) from ошибка
    if проверенный_реестр != ожидаемый_реестр:
        raise ОшибкаКонтракта(
            "разобранный реестр изменился до проверки точной вершины ветки"
        )
    return вершина


def ссылка_резервации(
    корень: Path,
    ссылка_ветки: str,
    идентификатор_задания: str,
) -> str:
    ветка = hashlib.sha256(ссылка_ветки.encode("utf-8")).hexdigest()
    задание = hashlib.sha256(идентификатор_задания.encode("utf-8")).hexdigest()
    return (
        f"{ПРОСТРАНСТВО_РЕЗЕРВАЦИЙ}/{идентичность_рабочей_копии(корень)}"
        f"/{ветка}/{задание}"
    )


def прочитать_идентификатор_объекта_ссылки(корень: Path, ссылка: str) -> str | None:
    символическая = выполнить_гит(корень, "symbolic-ref", "--quiet", ссылка)
    if символическая.returncode == 0:
        raise ОшибкаКонтракта(
            "служебная ссылка резервации не может быть символической"
        )
    if символическая.returncode != 1:
        raise ОшибкаКонтракта(
            "не удалось проверить вид служебной ссылки резервации"
        )
    результат = выполнить_гит(
        корень,
        "rev-parse",
        "--verify",
        "--quiet",
        ссылка,
    )
    if результат.returncode == 1:
        return None
    if результат.returncode != 0:
        raise ОшибкаКонтракта("не удалось прочитать служебную ссылку резервации")
    идентификатор_объекта = результат.stdout.strip()
    if ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(идентификатор_объекта) is None:
        raise ОшибкаКонтракта(
            "служебная ссылка резервации вернула неверный идентификатор объекта"
        )
    return идентификатор_объекта


def канонический_текст_резервации(резервация: dict[str, object]) -> str:
    return json.dumps(
        резервация,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ) + "\n"


def проверить_универсальный_идентификатор(значение: object, путь: str) -> str:
    строка = потребовать_строку(значение, путь)
    try:
        разобранный = uuid.UUID(строка)
    except ValueError as ошибка:
        raise ОшибкаКонтракта(f"{путь}: ожидался канонический UUID") from ошибка
    if str(разобранный) != строка:
        raise ОшибкаКонтракта(f"{путь}: ожидался канонический UUID")
    return строка


def проверить_резервацию(
    значение: object,
    ожидаемая_ветка: str,
    ожидаемое_задание: str,
) -> dict[str, object]:
    резервация = потребовать_объект(значение, "резервация")
    проверить_поля(резервация, ПОЛЯ_РЕЗЕРВАЦИИ, "резервация")
    if резервация["версия_схемы"] != 2:
        raise ОшибкаКонтракта(
            "резервация.версия_схемы: поддерживается только версия 2"
        )
    if резервация["branch_ref"] != ожидаемая_ветка:
        raise ОшибкаКонтракта("резервация принадлежит другой ветке")
    if резервация["job_id"] != ожидаемое_задание:
        raise ОшибкаКонтракта("резервация принадлежит другому заданию")
    if (
        ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(
            str(резервация["selection_head"])
        )
        is None
    ):
        raise ОшибкаКонтракта("резервация.selection_head имеет неверный формат")
    if ШАБЛОН_КЛЮЧА_ЗАПУСКА.fullmatch(str(резервация["run_key"])) is None:
        raise ОшибкаКонтракта("резервация.run_key имеет неверный формат")
    if not isinstance(резервация["trigger_occurrence"], dict):
        raise ОшибкаКонтракта(
            "резервация.trigger_occurrence имеет неверный формат"
        )
    проверить_универсальный_идентификатор(
        резервация["идентификатор_попытки"],
        "резервация.идентификатор_попытки",
    )
    for поле in (
        "версия_схемы_реестра",
        "поколение_реестра",
        "spec_generation",
    ):
        потребовать_целое(резервация[поле], f"резервация.{поле}", 1)
    if not isinstance(резервация["курсор_до"], dict):
        raise ОшибкаКонтракта("резервация.курсор_до имеет неверный формат")
    фаза = потребовать_строку(резервация["фаза"], "резервация.фаза")
    if фаза not in ФАЗЫ_РЕЗЕРВАЦИИ:
        raise ОшибкаКонтракта("резервация.фаза имеет неизвестное значение")
    исход = резервация["исход"]
    if фаза == "завершён":
        if исход not in ИСХОДЫ_РЕЗЕРВАЦИИ:
            raise ОшибкаКонтракта(
                "завершённая резервация не имеет точного исхода"
            )
    elif исход is not None:
        raise ОшибкаКонтракта("незавершённая резервация не может иметь исход")
    идентификатор_задачи = резервация["идентификатор_созданной_задачи"]
    if фаза in {"задача_создана", "завершён"} and идентификатор_задачи is not None:
        потребовать_строку(
            идентификатор_задачи,
            "резервация.идентификатор_созданной_задачи",
        )
    elif идентификатор_задачи is not None:
        raise ОшибкаКонтракта(
            "резервация преждевременно содержит созданную задачу"
        )
    подтверждение = резервация["подтверждение_результата"]
    if исход == "успех":
        потребовать_строку(
            подтверждение,
            "резервация.подтверждение_результата",
        )
    elif подтверждение is not None:
        raise ОшибкаКонтракта("резервация содержит подтверждение без успеха")
    идентификатор_задачи = резервация["task_id"]
    поколение_очереди = резервация["generation"]
    if идентификатор_задачи is not None:
        потребовать_строку(
            идентификатор_задачи,
            "резервация.task_id",
        )
        if фаза not in {"вызов_мог_состояться", "задача_создана", "завершён"}:
            raise ОшибкаКонтракта(
                "резервация преждевременно привязана к исполнителю"
            )
    if поколение_очереди is not None:
        потребовать_строку(
            поколение_очереди,
            "резервация.generation",
        )
        if идентификатор_задачи is None:
            raise ОшибкаКонтракта(
                "резервация содержит generation без task_id"
            )
    return резервация


def прочитать_резервацию(
    корень: Path,
    ссылка: str,
    ожидаемая_ветка: str,
    ожидаемое_задание: str,
) -> tuple[dict[str, object] | None, str | None]:
    идентификатор_объекта = прочитать_идентификатор_объекта_ссылки(корень, ссылка)
    if идентификатор_объекта is None:
        return None, None
    тип = выполнить_гит_строго(
        корень,
        "проверить тип объекта резервации",
        "cat-file",
        "-t",
        идентификатор_объекта,
    ).stdout.strip()
    if тип != "blob":
        raise ОшибкаКонтракта(
            "служебная ссылка резервации не указывает на объект-данные"
        )
    сырой = выполнить_гит_строго(
        корень,
        "прочитать объект-данные резервации",
        "cat-file",
        "blob",
        идентификатор_объекта,
    ).stdout
    try:
        значение = json.loads(
            сырой,
            object_pairs_hook=собрать_объект_без_повторов,
        )
    except (UnicodeError, json.JSONDecodeError) as ошибка:
        raise ОшибкаКонтракта("объект-данные Git резервации повреждён") from ошибка
    резервация = проверить_резервацию(значение, ожидаемая_ветка, ожидаемое_задание)
    if сырой != канонический_текст_резервации(резервация):
        raise ОшибкаКонтракта(
            "объект-данные Git резервации имеет неканонические байты"
        )
    return резервация, идентификатор_объекта


def записать_объект_резервации(
    корень: Path,
    резервация: dict[str, object],
    ветка: str,
    задание: str,
) -> str:
    проверить_резервацию(резервация, ветка, задание)
    результат = выполнить_гит_строго(
        корень,
        "записать объект-данные резервации",
        "hash-object",
        "-w",
        "--stdin",
        вход=канонический_текст_резервации(резервация),
    )
    идентификатор_объекта = результат.stdout.strip()
    if ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(идентификатор_объекта) is None:
        raise ОшибкаКонтракта(
            "Git не вернул идентификатор объекта новой резервации"
        )
    return идентификатор_объекта


def заменить_резервацию_сравнением(
    корень: Path,
    ссылка: str,
    прежний_идентификатор_объекта: str | None,
    новый_идентификатор_объекта: str,
    ветка: str | None = None,
    вершина: str | None = None,
) -> bool:
    if (ветка is None) != (вершина is None):
        raise ОшибкаКонтракта(
            "неполная проверка вершины ветки для сравнения и замены"
        )
    if ветка is not None and вершина is not None:
        команда = (
            f"create {ссылка} {новый_идентификатор_объекта}\n"
            if прежний_идентификатор_объекта is None
            else f"update {ссылка} {новый_идентификатор_объекта} {прежний_идентификатор_объекта}\n"
        )
        транзакция = (
            "start\n"
            f"verify {ветка} {вершина}\n"
            f"{команда}"
            "prepare\n"
            "commit\n"
        )
        результат = выполнить_гит(
            корень,
            "update-ref",
            "--no-deref",
            "--stdin",
            вход=транзакция,
        )
    else:
        результат = выполнить_гит(
            корень,
            "update-ref",
            "--no-deref",
            ссылка,
            новый_идентификатор_объекта,
            прежний_идентификатор_объекта or "",
        )
    if результат.returncode == 0:
        return True
    if ветка is not None and вершина is not None:
        if вершина_ветки(корень, ветка) != вершина:
            raise ОшибкаКонтракта(
                "вершина ветки изменилась до сравнения и замены резервации"
            )
    if прочитать_идентификатор_объекта_ссылки(корень, ссылка) != прежний_идентификатор_объекта:
        return False
    подробность = результат.stderr.strip() or "Git не вернул текст ошибки"
    raise ОшибкаКонтракта(
        f"не удалось атомарно заменить резервацию: {подробность}"
    )


def проверить_ожидания_выбора(
    выбор: dict[str, object],
    ожидаемое_задание: str,
    ожидаемое_поколение: int,
    ожидаемое_поколение_реестра: int,
    ожидаемый_ключ_запуска: str,
) -> None:
    if выбор["состояние"] != "выбрано":
        raise ОшибкаКонтракта("готовое задание отсутствует")
    if (
        выбор.get("job_id") != ожидаемое_задание
        or выбор.get("spec_generation") != ожидаемое_поколение
        or выбор.get("поколение_реестра") != ожидаемое_поколение_реестра
        or выбор.get("run_key") != ожидаемый_ключ_запуска
    ):
        raise ОшибкаКонтракта("ожидаемый выбор задания изменился")


def тот_же_запуск(
    резервация: dict[str, object],
    выбор: dict[str, object],
    вершина: str,
    реестр: dict[str, object],
) -> bool:
    return (
        резервация["branch_ref"] == выбор["branch_ref"]
        and резервация["selection_head"] == вершина
        and резервация["идентификатор_реестра"] == выбор["идентификатор_реестра"]
        and резервация["версия_схемы_реестра"] == выбор["версия_схемы_реестра"]
        and резервация["поколение_реестра"] == выбор["поколение_реестра"]
        and резервация["хэш_реестра"] == хэш_реестра(реестр)
        and резервация["job_id"] == выбор["job_id"]
        and резервация["spec_generation"] == выбор["spec_generation"]
        and резервация["trigger_occurrence"] == выбор["trigger_occurrence"]
        and резервация["run_key"] == выбор["run_key"]
    )


def подготовить_выбор_для_мутации(
    корень_сырой: str,
    путь_реестра: str,
    путь_схемы: str,
    источник_наблюдений: str | dict[str, object],
    ожидаемое_задание: str,
    ожидаемое_поколение: int,
    ожидаемое_поколение_реестра: int,
    ожидаемый_ключ_запуска: str,
) -> tuple[
    Path,
    dict[str, object],
    dict[str, object],
    str,
    dict[str, object],
]:
    корень = проверить_корень_рабочей_копии(корень_сырой)
    проверить_схему(прочитать_данные(путь_схемы, "схема"))
    реестр = проверить_реестр(
        прочитать_данные(путь_реестра, "реестр"),
        корень,
    )
    наблюдения = проверить_наблюдения(
        источник_наблюдений
        if isinstance(источник_наблюдений, dict)
        else прочитать_данные(источник_наблюдений, "наблюдения")
    )
    выбор = вычислить_выбор(реестр, наблюдения)
    проверить_ожидания_выбора(
        выбор,
        ожидаемое_задание,
        ожидаемое_поколение,
        ожидаемое_поколение_реестра,
        ожидаемый_ключ_запуска,
    )
    ветка = проверить_ссылку_ветки(выбор["branch_ref"], "выбор.branch_ref")
    вершина = проверить_авторитетный_реестр(
        корень,
        путь_реестра,
        ветка,
        реестр,
    )
    задание = найти_задание(реестр, ожидаемое_задание)
    return корень, реестр, выбор, вершина, задание



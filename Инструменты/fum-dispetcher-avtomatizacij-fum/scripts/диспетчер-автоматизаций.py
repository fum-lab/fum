class ОшибкаКонтракта(RuntimeError):
    """Нарушение закрытого контракта реестра или наблюдений."""


def собрать_объект_без_повторов(
    пары: list[tuple[str, object]],
) -> dict[str, object]:
    объект: dict[str, object] = {}
    for ключ, значение in пары:
        if ключ in объект:
            raise ОшибкаКонтракта(f"повтор ключа JSON: {ключ}")
        объект[ключ] = значение
    return объект


def канонический_текст(значение: object) -> str:
    return json.dumps(
        значение,
        ensure_ascii=False,
        indent=2,
        sort_keys=True,
    ) + "\n"


def прочитать_данные(путь: str | Path, назначение: str) -> object:
    файл = Path(путь)
    if файл.is_symlink() or not файл.is_file():
        raise ОшибкаКонтракта(f"{назначение} должен быть обычным файлом")
    try:
        return json.loads(
            файл.read_text(encoding="utf-8"),
            object_pairs_hook=собрать_объект_без_повторов,
        )
    except (OSError, UnicodeError, json.JSONDecodeError) as ошибка:
        raise ОшибкаКонтракта(
            f"{назначение} не является корректным UTF-8 JSON"
        ) from ошибка


def потребовать_объект(значение: object, путь: str) -> dict[str, object]:
    if not isinstance(значение, dict):
        raise ОшибкаКонтракта(f"{путь}: ожидался объект")
    return значение


def потребовать_массив(значение: object, путь: str) -> list[object]:
    if not isinstance(значение, list):
        raise ОшибкаКонтракта(f"{путь}: ожидался массив")
    return значение


def проверить_поля(
    объект: dict[str, object],
    обязательные: frozenset[str],
    путь: str,
) -> None:
    неизвестные = sorted(set(объект) - обязательные)
    if неизвестные:
        raise ОшибкаКонтракта(
            f"{путь}: неизвестные поля: {', '.join(неизвестные)}"
        )
    отсутствующие = sorted(обязательные - set(объект))
    if отсутствующие:
        точное_поле = отсутствующие[0]
        raise ОшибкаКонтракта(
            f"{путь}.{точное_поле}: отсутствует обязательное поле"
        )


def потребовать_строку(значение: object, путь: str) -> str:
    if (
        not isinstance(значение, str)
        or not значение
        or значение.strip() != значение
        or any(символ in значение for символ in "\r\n\0")
    ):
        raise ОшибкаКонтракта(f"{путь}: ожидалась непустая однострочная строка")
    return значение


def потребовать_целое(
    значение: object,
    путь: str,
    минимум: int = 0,
) -> int:
    if type(значение) is not int or значение < минимум:
        raise ОшибкаКонтракта(
            f"{путь}: ожидалось целое число не меньше {минимум}"
        )
    return значение


def проверить_ссылку_ветки(значение: object, путь: str) -> str:
    ссылка = потребовать_строку(значение, путь)
    if not ШАБЛОН_ССЫЛКИ_ВЕТКИ.fullmatch(ссылка):
        raise ОшибкаКонтракта(f"{путь}: небезопасный branch_ref")
    return ссылка


def проверить_путь_проекта(значение: object, путь: str) -> str:
    строка = потребовать_строку(значение, путь)
    адрес = PurePosixPath(строка)
    if (
        адрес.is_absolute()
        or строка.startswith(("~", "file://"))
        or "\\" in строка
        or any(часть in {"", ".", ".."} for часть in адрес.parts)
    ):
        raise ОшибкаКонтракта(f"{путь}: небезопасный путь проекта")
    return строка


def проверить_корень_рабочей_копии(значение: str | Path) -> Path:
    исходный_путь = Path(значение)
    if исходный_путь.is_symlink():
        raise ОшибкаКонтракта(
            "корень рабочей копии не должен быть символической ссылкой"
        )
    try:
        корень = исходный_путь.resolve(strict=True)
    except OSError as ошибка:
        raise ОшибкаКонтракта("корень рабочей копии недоступен") from ошибка
    if not корень.is_dir():
        raise ОшибкаКонтракта("корень рабочей копии должен быть каталогом")
    маркер_гит = корень / ".git"
    if маркер_гит.is_symlink() or not (
        маркер_гит.is_dir() or маркер_гит.is_file()
    ):
        raise ОшибкаКонтракта(
            "корень рабочей копии должен содержать обычный маркер Git"
        )
    return корень


def проверить_проект_в_рабочей_копии(
    реестр: dict[str, object],
    корень: Path,
) -> None:
    if реестр["якорь_рабочей_копии"] != ".":
        raise ОшибкаКонтракта(
            "реестр.якорь_рабочей_копии: версия 1 требует точный якорь ."
        )
    относительный = проверить_путь_проекта(
        реестр["путь_проекта"],
        "реестр.путь_проекта",
    )
    кандидат = корень
    for часть in PurePosixPath(относительный).parts:
        кандидат = кандидат / часть
        if кандидат.is_symlink():
            raise ОшибкаКонтракта(
                "реестр.путь_проекта: путь содержит символическую ссылку"
            )
    if not кандидат.is_file():
        raise ОшибкаКонтракта(
            "реестр.путь_проекта: проект не найден в рабочей копии"
        )
    try:
        кандидат.resolve(strict=True).relative_to(корень)
    except (OSError, ValueError) as ошибка:
        raise ОшибкаКонтракта(
            "реестр.путь_проекта: проект выходит за пределы рабочей копии"
        ) from ошибка


def разобрать_момент(значение: object, путь: str) -> datetime:
    строка = потребовать_строку(значение, путь)
    if not ШАБЛОН_МОМЕНТА.fullmatch(строка):
        raise ОшибкаКонтракта(f"{путь}: нужен точный UTC-момент с суффиксом Z")
    try:
        момент = datetime.fromisoformat(строка.removesuffix("Z") + "+00:00")
    except ValueError as ошибка:
        raise ОшибкаКонтракта(f"{путь}: календарно невозможный момент") from ошибка
    if момент.tzinfo != timezone.utc:
        raise ОшибкаКонтракта(f"{путь}: момент должен быть в UTC")
    return момент


def представить_момент(момент: datetime) -> str:
    return момент.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def проверить_схему(значение: object) -> None:
    схема = потребовать_объект(значение, "схема")
    if схема.get("$id") != ИДЕНТИФИКАТОР_СХЕМЫ:
        raise ОшибкаКонтракта("схема: неверный $id")
    if схема.get("type") != "object" or схема.get("additionalProperties") is not False:
        raise ОшибкаКонтракта("схема: корневой объект должен быть закрыт")
    if set(схема.get("required", [])) != ПОЛЯ_РЕЕСТРА:
        raise ОшибкаКонтракта("схема: обязательные поля реестра не совпадают")
    определения = потребовать_объект(схема.get("$defs"), "схема.$defs")
    задание = потребовать_объект(
        определения.get("задание"),
        "схема.$defs.задание",
    )
    if set(задание.get("required", [])) != ПОЛЯ_ЗАДАНИЯ:
        raise ОшибкаКонтракта("схема: обязательные поля задания не совпадают")
    if задание.get("allOf") != [ОГРАНИЧЕНИЕ_ИСПОЛНИТЕЛЯ_ИЗМЕНЕНИЙ]:
        raise ОшибкаКонтракта(
            "схема: связь мутирующего эффекта с исполнителем не совпадает"
        )
    свойства_реестра = потребовать_объект(
        схема.get("properties"),
        "схема.properties",
    )
    поле_ссылки_реестра = потребовать_объект(
        свойства_реестра.get("branch_ref"),
        "схема.properties.branch_ref",
    )
    цель = потребовать_объект(определения.get("цель"), "схема.$defs.цель")
    свойства_цели = потребовать_объект(
        цель.get("properties"),
        "схема.$defs.цель.properties",
    )
    поле_ссылки_цели = потребовать_объект(
        свойства_цели.get("branch_ref"),
        "схема.$defs.цель.properties.branch_ref",
    )
    for поле_ссылки in (поле_ссылки_реестра, поле_ссылки_цели):
        if поле_ссылки.get("pattern") != СТРОКА_ШАБЛОНА_ССЫЛКИ_ВЕТКИ:
            raise ОшибкаКонтракта(
                "схема: шаблон безопасного branch_ref не совпадает"
            )


def проверить_тип_и_контракт(значение: object, путь: str) -> None:
    объект = потребовать_объект(значение, путь)
    проверить_поля(объект, ПОЛЯ_ТИПА_И_КОНТРАКТА, путь)
    потребовать_строку(объект["тип"], f"{путь}.тип")
    потребовать_строку(объект["контракт"], f"{путь}.контракт")


def проверить_триггер(значение: object, путь: str) -> str:
    триггер = потребовать_объект(значение, путь)
    тип = потребовать_строку(триггер.get("тип"), f"{путь}.тип")
    if тип == "расписание":
        if set(триггер) != ПОЛЯ_РАСПИСАНИЯ:
            raise ОшибкаКонтракта(f"{путь}: противоречивый триггер")
        разобрать_момент(триггер["якорь"], f"{путь}.якорь")
        потребовать_целое(
            триггер["интервал_секунды"],
            f"{путь}.интервал_секунды",
            1,
        )
        return тип
    if тип == "порог_подтверждённых_событий":
        if set(триггер) != ПОЛЯ_ПОРОГА:
            raise ОшибкаКонтракта(f"{путь}: противоречивый триггер")
        потребовать_строку(триггер["тип_события"], f"{путь}.тип_события")
        потребовать_целое(триггер["каждые"], f"{путь}.каждые", 1)
        return тип
    raise ОшибкаКонтракта(f"{путь}.тип: неизвестный тип триггера")


def проверить_условия(значение: object, путь: str) -> None:
    условия = потребовать_массив(значение, путь)
    идентификаторы: set[str] = set()
    for номер, сырое_условие in enumerate(условия):
        адрес = f"{путь}[{номер}]"
        условие = потребовать_объект(сырое_условие, адрес)
        проверить_поля(условие, ПОЛЯ_УСЛОВИЯ, адрес)
        идентификатор = потребовать_строку(
            условие["идентификатор"],
            f"{адрес}.идентификатор",
        )
        потребовать_строку(условие["наблюдение"], f"{адрес}.наблюдение")
        if type(условие["ожидается"]) is not bool:
            raise ОшибкаКонтракта(
                f"{адрес}.ожидается: ожидалось логическое значение"
            )
        if идентификатор in идентификаторы:
            raise ОшибкаКонтракта(f"{путь}: повтор идентификатора условия")
        идентификаторы.add(идентификатор)


def проверить_курсор(
    значение: object,
    путь: str,
    тип_триггера: str,
    триггер: dict[str, object],
) -> None:
    курсор = потребовать_объект(значение, путь)
    тип_курсора = потребовать_строку(курсор.get("тип"), f"{путь}.тип")
    if тип_триггера == "расписание":
        if тип_курсора != "расписание":
            raise ОшибкаКонтракта(f"{путь}: курсор не соответствует триггеру")
        проверить_поля(курсор, ПОЛЯ_КУРСОРА_РАСПИСАНИЯ, путь)
        последнее = курсор["последнее_наступление"]
        if последнее is not None:
            последний_момент = разобрать_момент(
                последнее,
                f"{путь}.последнее_наступление",
            )
            якорь = разобрать_момент(
                триггер["якорь"],
                "триггер.якорь",
            )
            if последний_момент < якорь:
                raise ОшибкаКонтракта(
                    f"{путь}.последнее_наступление: момент раньше якоря"
                )
            интервал = триггер["интервал_секунды"]
            if type(интервал) is not int:
                raise ОшибкаКонтракта("внутренняя ошибка проверки расписания")
            смещение = int((последний_момент - якорь).total_seconds())
            if смещение % интервал != 0:
                raise ОшибкаКонтракта(
                    f"{путь}.последнее_наступление: "
                    "не совпадает с сеткой расписания"
                )
        return

    if тип_курсора != "подтверждённые_события":
        raise ОшибкаКонтракта(f"{путь}: курсор не соответствует триггеру")
    проверить_поля(курсор, ПОЛЯ_КУРСОРА_СОБЫТИЙ, путь)
    число = потребовать_целое(
        курсор["последнее_число_подтверждённых_событий"],
        f"{путь}.последнее_число_подтверждённых_событий",
    )
    последний_идентификатор = курсор["последний_идентификатор_события"]
    if последний_идентификатор is not None:
        потребовать_строку(
            последний_идентификатор,
            f"{путь}.последний_идентификатор_события",
        )
    следующий = потребовать_целое(
        курсор["следующий_порог"],
        f"{путь}.следующий_порог",
        1,
    )
    каждые = триггер["каждые"]
    if type(каждые) is not int:
        raise ОшибкаКонтракта("внутренняя ошибка проверки триггера")
    ожидаемый = (число // каждые + 1) * каждые
    if следующий != ожидаемый:
        raise ОшибкаКонтракта(
            f"{путь}.следующий_порог: порог не согласован с курсором"
        )


def проверить_защиту(
    значение: object,
    путь: str,
    поколение: int,
) -> None:
    защита = потребовать_объект(значение, путь)
    проверить_поля(защита, ПОЛЯ_ЗАЩИТЫ, путь)
    if защита["тип"] != "поколение_и_наступление":
        raise ОшибкаКонтракта(f"{путь}.тип: неизвестный fence")
    if защита["область"] != "рабочая_копия_ветка_задание":
        raise ОшибкаКонтракта(f"{путь}.область: неизвестная область fence")
    поколение_защиты = потребовать_целое(
        защита["поколение"],
        f"{путь}.поколение",
        1,
    )
    if поколение_защиты != поколение:
        raise ОшибкаКонтракта(
            f"{путь}.поколение: не совпадает с поколением задания"
        )


def проверить_эффект(значение: object, путь: str) -> str:
    эффект = потребовать_объект(значение, путь)
    проверить_поля(эффект, ПОЛЯ_ЭФФЕКТА, путь)
    класс = потребовать_строку(эффект["класс"], f"{путь}.класс")
    политика = потребовать_строку(эффект["политика"], f"{путь}.политика")
    ожидаемая_политика = КЛАССЫ_И_ПОЛИТИКИ_ЭФФЕКТА.get(класс)
    if ожидаемая_политика is None:
        raise ОшибкаКонтракта(f"{путь}.класс: неизвестный класс эффекта")
    if политика != ожидаемая_политика:
        raise ОшибкаКонтракта(f"{путь}: класс и политика не согласованы")
    return класс


def проверить_исполнителя(
    значение: object,
    путь: str,
    класс_эффекта: str,
) -> None:
    исполнитель = потребовать_объект(значение, путь)
    проверить_поля(исполнитель, ПОЛЯ_ТИПА_И_КОНТРАКТА, путь)
    тип = потребовать_строку(исполнитель["тип"], f"{путь}.тип")
    контракт = потребовать_строку(
        исполнитель["контракт"],
        f"{путь}.контракт",
    )
    if ИСПОЛНИТЕЛИ.get(тип) != контракт:
        raise ОшибкаКонтракта(f"{путь}: неизвестный исполнитель")
    if (
        класс_эффекта != "только_чтение"
        and тип != "обычная_корневая_задача_Codex"
    ):
        raise ОшибкаКонтракта(
            f"{путь}: мутирующий эффект требует обычную корневую задачу"
        )


def проверить_политику_ошибки(значение: object, путь: str) -> None:
    политика = потребовать_объект(значение, путь)
    проверить_поля(политика, ПОЛЯ_ПОЛИТИКИ_ОШИБКИ, путь)
    if политика["режим"] != "закрытый_отказ":
        raise ОшибкаКонтракта(f"{путь}.режим: поддерживается закрытый_отказ")
    if политика["повтор"] not in ПОВТОРЫ_ПОСЛЕ_ОШИБКИ:
        raise ОшибкаКонтракта(f"{путь}.повтор: неизвестная политика повтора")
    if политика["неоднозначный_результат"] not in НЕОДНОЗНАЧНЫЕ_РЕЗУЛЬТАТЫ:
        raise ОшибкаКонтракта(
            f"{путь}.неоднозначный_результат: неизвестная политика"
        )


def проверить_задание(
    значение: object,
    номер: int,
    реестр: dict[str, object],
) -> str:
    путь = f"реестр.задания[{номер}]"
    задание = потребовать_объект(значение, путь)
    проверить_поля(задание, ПОЛЯ_ЗАДАНИЯ, путь)
    идентификатор_задания = потребовать_строку(
        задание["job_id"],
        f"{путь}.job_id",
    )
    if not ШАБЛОН_ИДЕНТИФИКАТОРА.fullmatch(идентификатор_задания):
        raise ОшибкаКонтракта(f"{путь}.job_id: неверный устойчивый идентификатор")
    поколение = потребовать_целое(
        задание["поколение"],
        f"{путь}.поколение",
        1,
    )
    потребовать_целое(задание["приоритет"], f"{путь}.приоритет")
    проверить_тип_и_контракт(задание["адаптер"], f"{путь}.адаптер")

    цель = потребовать_объект(задание["цель"], f"{путь}.цель")
    проверить_поля(цель, ПОЛЯ_ЦЕЛИ, f"{путь}.цель")
    проверить_ссылку_ветки(цель["branch_ref"], f"{путь}.цель.branch_ref")
    проверить_путь_проекта(цель["путь_проекта"], f"{путь}.цель.путь_проекта")
    for поле in ПОЛЯ_ЦЕЛИ:
        if цель[поле] != реестр[поле]:
            raise ОшибкаКонтракта(
                f"{путь}.цель.{поле}: не совпадает с веточным реестром"
            )

    триггер = потребовать_объект(задание["триггер"], f"{путь}.триггер")
    тип_триггера = проверить_триггер(триггер, f"{путь}.триггер")
    проверить_условия(задание["условия_допуска"], f"{путь}.условия_допуска")

    состояние = потребовать_строку(задание["состояние"], f"{путь}.состояние")
    if состояние not in СОСТОЯНИЯ:
        raise ОшибкаКонтракта(f"{путь}.состояние: недопустимое состояние")

    класс_эффекта = проверить_эффект(задание["эффект"], f"{путь}.эффект")
    проверить_исполнителя(
        задание["исполнитель"],
        f"{путь}.исполнитель",
        класс_эффекта,
    )
    проверить_защиту(
        задание["защита_поколения"],
        f"{путь}.защита_поколения",
        поколение,
    )
    проверить_курсор(
        задание["курсор_результата"],
        f"{путь}.курсор_результата",
        тип_триггера,
        триггер,
    )
    проверить_политику_ошибки(
        задание["политика_ошибки"],
        f"{путь}.политика_ошибки",
    )
    return идентификатор_задания


def проверить_реестр(
    значение: object,
    корень: Path,
) -> dict[str, object]:
    реестр = потребовать_объект(значение, "реестр")
    проверить_поля(реестр, ПОЛЯ_РЕЕСТРА, "реестр")
    if реестр["версия_схемы"] != ВЕРСИЯ_СХЕМЫ:
        raise ОшибкаКонтракта(
            "реестр.версия_схемы: поддерживается только версия 1"
        )
    потребовать_строку(
        реестр["идентификатор_реестра"],
        "реестр.идентификатор_реестра",
    )
    потребовать_целое(
        реестр["поколение_реестра"],
        "реестр.поколение_реестра",
        1,
    )
    проверить_ссылку_ветки(реестр["branch_ref"], "реестр.branch_ref")
    потребовать_строку(
        реестр["идентификатор_проекта"],
        "реестр.идентификатор_проекта",
    )
    проверить_проект_в_рабочей_копии(реестр, корень)
    задания = потребовать_массив(реестр["задания"], "реестр.задания")
    идентификаторы: set[str] = set()
    for номер, задание in enumerate(задания):
        идентификатор_задания = проверить_задание(задание, номер, реестр)
        if идентификатор_задания in идентификаторы:
            raise ОшибкаКонтракта(
                f"реестр.задания: повтор job_id {идентификатор_задания}"
            )
        идентификаторы.add(идентификатор_задания)
    return реестр


def проверить_наблюдения(значение: object) -> dict[str, object]:
    наблюдения = потребовать_объект(значение, "наблюдения")
    проверить_поля(наблюдения, ПОЛЯ_НАБЛЮДЕНИЙ, "наблюдения")
    if наблюдения["версия_схемы"] != 1:
        raise ОшибкаКонтракта(
            "наблюдения.версия_схемы: поддерживается только версия 1"
        )
    разобрать_момент(наблюдения["момент"], "наблюдения.момент")
    условия = потребовать_объект(наблюдения["условия"], "наблюдения.условия")
    for имя, значение_условия in условия.items():
        потребовать_строку(имя, "наблюдения.условия.<имя>")
        if type(значение_условия) is not bool:
            raise ОшибкаКонтракта(
                f"наблюдения.условия.{имя}: ожидалось логическое значение"
            )
    события = потребовать_объект(
        наблюдения["подтверждённые_события"],
        "наблюдения.подтверждённые_события",
    )
    for имя, число in события.items():
        потребовать_строку(имя, "наблюдения.подтверждённые_события.<имя>")
        потребовать_целое(
            число,
            f"наблюдения.подтверждённые_события.{имя}",
        )
    return наблюдения


def вычислить_наступление(
    задание: dict[str, object],
    наблюдения: dict[str, object],
) -> str | None:
    триггер = потребовать_объект(задание["триггер"], "задание.триггер")
    курсор = потребовать_объект(
        задание["курсор_результата"],
        "задание.курсор_результата",
    )
    if триггер["тип"] == "расписание":
        момент = разобрать_момент(наблюдения["момент"], "наблюдения.момент")
        якорь = разобрать_момент(триггер["якорь"], "задание.триггер.якорь")
        if момент < якорь:
            return None
        интервал = триггер["интервал_секунды"]
        if type(интервал) is not int:
            raise ОшибкаКонтракта("внутренняя ошибка интервала")
        число_интервалов = int((момент - якорь).total_seconds()) // интервал
        наступление = якорь + timedelta(seconds=число_интервалов * интервал)
        последнее = курсор["последнее_наступление"]
        if последнее is not None:
            последний_момент = разобрать_момент(
                последнее,
                "задание.курсор_результата.последнее_наступление",
            )
            if наступление <= последний_момент:
                return None
        return представить_момент(наступление)

    тип_события = триггер["тип_события"]
    порог = курсор["следующий_порог"]
    каждые = триггер["каждые"]
    if (
        not isinstance(тип_события, str)
        or type(порог) is not int
        or type(каждые) is not int
    ):
        raise ОшибкаКонтракта("внутренняя ошибка порогового триггера")
    события = потребовать_объект(
        наблюдения["подтверждённые_события"],
        "наблюдения.подтверждённые_события",
    )
    число = события.get(тип_события, 0)
    if type(число) is not int or число < порог:
        return None
    начало = порог - каждые + 1
    return f"{тип_события}:{начало}-{порог}"


def вычислить_невыполненные_условия(
    задание: dict[str, object],
    наблюдения: dict[str, object],
) -> list[str]:
    значения = потребовать_объект(наблюдения["условия"], "наблюдения.условия")
    невыполненные: list[str] = []
    условия = потребовать_массив(
        задание["условия_допуска"],
        "задание.условия_допуска",
    )
    for сырое_условие in условия:
        условие = потребовать_объект(сырое_условие, "задание.условие")
        if значения.get(условие["наблюдение"]) is not условие["ожидается"]:
            идентификатор = условие["идентификатор"]
            if isinstance(идентификатор, str):
                невыполненные.append(идентификатор)
    return невыполненные


def моделировать_задание(
    задание: dict[str, object],
    наблюдения: dict[str, object],
) -> dict[str, object]:
    наступление = вычислить_наступление(задание, наблюдения)
    невыполненные = вычислить_невыполненные_условия(задание, наблюдения)
    состояние = задание["состояние"]
    триггер_наступил = наступление is not None
    условия_выполнены = not невыполненные
    состояние_разрешает = состояние == "active"
    готово = триггер_наступил and условия_выполнены and состояние_разрешает

    if состояние == "paused":
        статус = "приостановлено"
    elif состояние == "blocked":
        статус = "заблокировано"
    elif состояние == "retired":
        статус = "выведено_из_эксплуатации"
    elif not триггер_наступил:
        статус = "ожидание_триггера"
    elif not условия_выполнены:
        статус = "ожидание_условий"
    else:
        статус = "готово"

    return {
        "job_id": задание["job_id"],
        "поколение": задание["поколение"],
        "наступление": наступление,
        "триггер_наступил": триггер_наступил,
        "невыполненные_условия": невыполненные,
        "условия_выполнены": условия_выполнены,
        "состояние_разрешает": состояние_разрешает,
        "готово": готово,
        "статус": статус,
    }


def смоделировать(
    реестр: dict[str, object],
    наблюдения: dict[str, object],
) -> dict[str, object]:
    задания = потребовать_массив(реестр["задания"], "реестр.задания")
    упорядоченные = sorted(
        (потребовать_объект(задание, "реестр.задание") for задание in задания),
        key=lambda задание: (задание["приоритет"], задание["job_id"]),
    )
    return {
        "идентификатор_реестра": реестр["идентификатор_реестра"],
        "поколение_реестра": реестр["поколение_реестра"],
        "состояние": "смоделирован",
        "задания": [
            моделировать_задание(задание, наблюдения)
            for задание in упорядоченные
        ],
    }


def построить_парсер() -> argparse.ArgumentParser:
    парсер = argparse.ArgumentParser(
        description="Проверить реестр заданий или автономно смоделировать тик."
    )
    команды = парсер.add_subparsers(dest="команда", required=True)
    для_проверки = команды.add_parser("проверить")
    для_симуляции = команды.add_parser("симулировать")
    for команда in (для_проверки, для_симуляции):
        команда.add_argument(
            "--корень-рабочей-копии",
            dest="корень_рабочей_копии",
            required=True,
        )
        команда.add_argument("--реестр", required=True)
        команда.add_argument("--схема", required=True)
        команда.add_argument("--json", dest="вывод_json", action="store_true")
    для_проверки.add_argument(
        "--без-вывода",
        dest="без_вывода",
        action="store_true",
    )
    для_симуляции.add_argument("--наблюдения", required=True)
    return парсер


def главная(аргументы: Sequence[str] | None = None) -> int:
    разобранные = построить_парсер().parse_args(аргументы)
    try:
        корень = проверить_корень_рабочей_копии(
            разобранные.корень_рабочей_копии
        )
        проверить_схему(прочитать_данные(разобранные.схема, "схема"))
        реестр = проверить_реестр(
            прочитать_данные(разобранные.реестр, "реестр"),
            корень,
        )
        if разобранные.команда == "проверить":
            задания = потребовать_массив(реестр["задания"], "реестр.задания")
            ответ: object = {
                "идентификатор_реестра": реестр["идентификатор_реестра"],
                "поколение_реестра": реестр["поколение_реестра"],
                "состояние": "корректен",
                "версия_схемы": реестр["версия_схемы"],
                "число_заданий": len(задания),
            }
        else:
            наблюдения = проверить_наблюдения(
                прочитать_данные(разобранные.наблюдения, "наблюдения")
            )
            ответ = смоделировать(реестр, наблюдения)
    except ОшибкаКонтракта as ошибка:
        ответ = {"состояние": "некорректен", "ошибка": str(ошибка)}
        if разобранные.вывод_json:
            sys.stdout.write(канонический_текст(ответ))
        else:
            sys.stderr.write(f"Ошибка: {ошибка}\n")
        return 2

    if getattr(разобранные, "без_вывода", False):
        return 0
    if разобранные.вывод_json:
        sys.stdout.write(канонический_текст(ответ))
    else:
        sys.stdout.write("Реестр корректен.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(главная())

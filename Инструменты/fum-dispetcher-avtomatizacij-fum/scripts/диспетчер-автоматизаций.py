def проверить_участника_очереди(
    значение: object,
    *,
    владелец: bool,
) -> dict[str, object]:
    общие = {"task_id", "ticket_id", "seq"}
    специальные = (
        {"generation", "base_head", "admitted_at", "admitted_at_epoch"}
        if владелец
        else {"registered_at", "registered_at_epoch", "acknowledged_head"}
    )
    участник = потребовать_объект(значение, "очередь.участник")
    if set(участник) != общие | специальные:
        raise ОшибкаКонтракта("участник очереди имеет неверный набор полей")
    проверить_оперативный_идентификатор(
        участник["task_id"],
        "очередь.task_id",
    )
    проверить_оперативный_идентификатор(
        участник["ticket_id"],
        "очередь.ticket_id",
    )
    потребовать_целое(участник["seq"], "очередь.seq", 1)
    вершина = участник["base_head" if владелец else "acknowledged_head"]
    if (
        not isinstance(вершина, str)
        or ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(вершина) is None
    ):
        raise ОшибкаКонтракта("участник очереди имеет неверную вершину")
    метка = участник["admitted_at" if владелец else "registered_at"]
    эпоха = участник[
        "admitted_at_epoch" if владелец else "registered_at_epoch"
    ]
    if not isinstance(метка, str) or not метка:
        raise ОшибкаКонтракта("участник очереди имеет неверную метку времени")
    if type(эпоха) not in {int, float} or (
        type(эпоха) is float and not math.isfinite(эпоха)
    ):
        raise ОшибкаКонтракта("участник очереди имеет неверный epoch")
    if владелец:
        проверить_оперативный_идентификатор(
            участник["generation"],
            "очередь.generation",
        )
    return участник


def проверить_завершение_очереди(значение: object) -> dict[str, object] | None:
    if значение is None:
        return None
    завершение = потребовать_объект(значение, "очередь.last_completion")
    вид = завершение.get("kind")
    поля = {"kind", "task_id", "generation", "head", "completed_at"}
    if вид == "committed":
        поля.add("base_head")
    elif вид != "finished_clean":
        raise ОшибкаКонтракта("завершение очереди имеет неизвестный kind")
    if set(завершение) != поля:
        raise ОшибкаКонтракта("завершение очереди имеет неверный набор полей")
    проверить_оперативный_идентификатор(
        завершение["task_id"],
        "очередь.last_completion.task_id",
    )
    проверить_оперативный_идентификатор(
        завершение["generation"],
        "очередь.last_completion.generation",
    )
    for поле in ("head", "base_head"):
        if поле not in завершение:
            continue
        вершина = завершение[поле]
        if (
            not isinstance(вершина, str)
            or ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(вершина) is None
        ):
            raise ОшибкаКонтракта(
                f"очередь.last_completion.{поле} имеет неверный формат"
            )
    if (
        not isinstance(завершение["completed_at"], str)
        or not завершение["completed_at"]
    ):
        raise ОшибкаКонтракта("завершение очереди не имеет метки времени")
    return завершение


def ссылка_журнала_завершений(корень: Path, ветка: str) -> str:
    хэш_ветки = hashlib.sha256(ветка.encode("utf-8")).hexdigest()
    return (
        f"{ПРОСТРАНСТВО_ЖУРНАЛОВ_ЗАВЕРШЕНИЙ}/"
        f"{идентичность_рабочей_копии(корень)}/{хэш_ветки}"
    )


def длина_идентификатора_объекта(корень: Path) -> int:
    формат = выполнить_гит_строго(
        корень,
        "определить формат объектов Git",
        "rev-parse",
        "--show-object-format=storage",
    ).stdout.strip()
    if формат == "sha1":
        return 40
    if формат == "sha256":
        return 64
    raise ОшибкаКонтракта("Git вернул неизвестный формат объектов")


def проверить_идентификатор_объекта_репозитория(
    значение: object,
    длина: int,
    путь: str,
) -> str:
    if (
        not isinstance(значение, str)
        or len(значение) != длина
        or re.fullmatch(r"[0-9a-f]+", значение) is None
    ):
        raise ОшибкаКонтракта(f"{путь} имеет неверный формат")
    return значение


def проверить_метку_журнала_завершений(
    значение: object,
    путь: str,
) -> str:
    if (
        not isinstance(значение, str)
        or ШАБЛОН_МЕТКИ_ЖУРНАЛА_ЗАВЕРШЕНИЙ.fullmatch(значение) is None
    ):
        raise ОшибкаКонтракта(f"{путь} имеет неверный формат")
    try:
        разобранная = datetime.fromisoformat(значение[:-1] + "+00:00")
    except ValueError as ошибка:
        raise ОшибкаКонтракта(f"{путь} содержит невозможную дату") from ошибка
    каноническая = разобранная.isoformat(timespec="milliseconds").replace(
        "+00:00",
        "Z",
    )
    if каноническая != значение:
        raise ОшибкаКонтракта(f"{путь} не является канонической UTC-меткой")
    return значение


def проверить_запись_журнала_завершений(
    значение: object,
    идентификатор_рабочей_копии: str,
    ветка: str,
    длина_объекта: int,
) -> dict[str, object]:
    запись = потребовать_объект(значение, "запись журнала завершений")
    if set(запись) != {
        "схема",
        "идентификатор_рабочей_копии",
        "ссылка_ветки",
        "завершение",
    }:
        raise ОшибкаКонтракта(
            "запись журнала завершений имеет неверный набор полей"
        )
    if (
        запись["схема"] != СХЕМА_ЖУРНАЛА_ЗАВЕРШЕНИЙ
        or запись["идентификатор_рабочей_копии"]
        != идентификатор_рабочей_копии
        or запись["ссылка_ветки"] != ветка
    ):
        raise ОшибкаКонтракта(
            "запись журнала завершений принадлежит другому контракту"
        )
    завершение = проверить_завершение_очереди(запись["завершение"])
    if завершение is None:
        raise ОшибкаКонтракта("запись журнала не содержит завершение")
    проверить_идентификатор_объекта_репозитория(
        завершение["head"],
        длина_объекта,
        "журнал.завершение.head",
    )
    if завершение["kind"] == "committed":
        проверить_идентификатор_объекта_репозитория(
            завершение["base_head"],
            длина_объекта,
            "журнал.завершение.base_head",
        )
    проверить_метку_журнала_завершений(
        завершение["completed_at"],
        "журнал.завершение.completed_at",
    )
    return запись


def канонические_байты_записи_журнала(
    запись: dict[str, object],
) -> bytes:
    return (
        json.dumps(
            запись,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        )
        + "\n"
    ).encode("utf-8")


def прочитать_коммиты_журнала_пакетом(
    корень: Path,
    объекты: list[str],
) -> dict[str, bytes]:
    вход = "".join(f"{объект}\n" for объект in объекты).encode("ascii")
    результат = выполнить_гит_байты(
        корень,
        "cat-file",
        "--batch",
        вход=вход,
    )
    if результат.returncode != 0:
        подробность = результат.stderr.decode(
            "utf-8",
            errors="replace",
        ).strip()
        raise ОшибкаКонтракта(
            "не удалось пакетно прочитать журнал завершений: "
            + (подробность or "Git не вернул текст ошибки")
        )
    сырой = результат.stdout
    позиция = 0
    прочитанные: dict[str, bytes] = {}
    for ожидаемый in объекты:
        конец_заголовка = сырой.find(b"\n", позиция)
        if конец_заголовка < 0:
            raise ОшибкаКонтракта(
                "пакетный ответ Git оборван до заголовка объекта"
            )
        try:
            части = сырой[позиция:конец_заголовка].decode("ascii").split(" ")
        except UnicodeDecodeError as ошибка:
            raise ОшибкаКонтракта(
                "пакетный ответ Git содержит не-ASCII заголовок"
            ) from ошибка
        if (
            len(части) != 3
            or части[0] != ожидаемый
            or части[1] != "commit"
            or not части[2].isdigit()
        ):
            raise ОшибкаКонтракта(
                "пакетный ответ Git не подтвердил точный commit журнала"
            )
        размер = int(части[2])
        начало = конец_заголовка + 1
        конец = начало + размер
        if конец >= len(сырой) or сырой[конец : конец + 1] != b"\n":
            raise ОшибкаКонтракта(
                "пакетный ответ Git содержит неверный размер объекта"
            )
        прочитанные[ожидаемый] = сырой[начало:конец]
        позиция = конец + 1
    if позиция != len(сырой):
        raise ОшибкаКонтракта(
            "пакетный ответ Git содержит лишние данные после объектов"
        )
    return прочитанные


def найти_завершение_в_журнале(
    корень: Path,
    ветка: str,
    идентификатор_задачи: str,
    поколение: str,
) -> tuple[dict[str, object] | None, str, str | None, str | None]:
    ссылка = ссылка_журнала_завершений(корень, ветка)
    вершина = прочитать_идентификатор_объекта_ссылки(корень, ссылка)
    if вершина is None:
        return None, ссылка, None, None
    длина_объекта = длина_идентификатора_объекта(корень)
    проверить_идентификатор_объекта_репозитория(
        вершина,
        длина_объекта,
        "вершина журнала завершений",
    )
    перечисление = выполнить_гит_строго(
        корень,
        "прочитать линейную историю журнала завершений",
        "rev-list",
        "--first-parent",
        вершина,
        "--",
    ).stdout
    объекты = перечисление.splitlines()
    if not объекты or объекты[0] != вершина:
        raise ОшибкаКонтракта("журнал завершений не имеет точной вершины")
    for номер, объект in enumerate(объекты):
        проверить_идентификатор_объекта_репозитория(
            объект,
            длина_объекта,
            f"журнал.объекты[{номер}]",
        )
    if len(объекты) != len(set(объекты)):
        raise ОшибкаКонтракта("журнал завершений содержит цикл или повтор объекта")
    пустое_дерево = выполнить_гит_байты(
        корень,
        "hash-object",
        "-t",
        "tree",
        "--stdin",
        вход=b"",
    )
    if пустое_дерево.returncode != 0:
        raise ОшибкаКонтракта("не удалось вычислить пустое дерево Git")
    try:
        объект_пустого_дерева = пустое_дерево.stdout.decode("ascii").strip()
    except UnicodeDecodeError as ошибка:
        raise ОшибкаКонтракта(
            "Git вернул не-ASCII идентификатор пустого дерева"
        ) from ошибка
    проверить_идентификатор_объекта_репозитория(
        объект_пустого_дерева,
        длина_объекта,
        "пустое дерево Git",
    )
    сырые_коммиты = прочитать_коммиты_журнала_пакетом(корень, объекты)
    идентичность = идентичность_рабочей_копии(корень)
    встреченные: set[tuple[str, str]] = set()
    найденное: dict[str, object] | None = None
    объект_найденного: str | None = None
    for номер, объект in enumerate(объекты):
        родитель = объекты[номер + 1] if номер + 1 < len(объекты) else None
        строки_заголовка = [f"tree {объект_пустого_дерева}"]
        if родитель is not None:
            строки_заголовка.append(f"parent {родитель}")
        строки_заголовка.extend(
            [ЗАГОЛОВОК_АВТОРА_ЖУРНАЛА, ЗАГОЛОВОК_КОММИТЕРА_ЖУРНАЛА]
        )
        ожидаемый_заголовок = "\n".join(строки_заголовка).encode("ascii")
        сырой_коммит = сырые_коммиты[объект]
        части = сырой_коммит.split(b"\n\n", 1)
        if len(части) != 2 or части[0] != ожидаемый_заголовок:
            raise ОшибкаКонтракта(
                "commit журнала имеет неверный закрытый конверт"
            )
        try:
            значение = json.loads(
                части[1].decode("utf-8"),
                object_pairs_hook=собрать_объект_без_повторов,
                parse_constant=lambda константа: (_ for _ in ()).throw(
                    ОшибкаКонтракта(
                        "журнал содержит неконечную константу " + константа
                    )
                ),
            )
        except (UnicodeError, json.JSONDecodeError) as ошибка:
            raise ОшибкаКонтракта(
                "commit журнала содержит повреждённый JSON"
            ) from ошибка
        запись = проверить_запись_журнала_завершений(
            значение,
            идентичность,
            ветка,
            длина_объекта,
        )
        if сырой_коммит != (
            ожидаемый_заголовок
            + b"\n\n"
            + канонические_байты_записи_журнала(запись)
        ):
            raise ОшибкаКонтракта(
                "commit журнала имеет неканонические байты"
            )
        завершение = потребовать_объект(
            запись["завершение"],
            "журнал.завершение",
        )
        ключ = (str(завершение["task_id"]), str(завершение["generation"]))
        if ключ in встреченные:
            raise ОшибкаКонтракта(
                "журнал завершений содержит повтор исполнителя и поколения"
            )
        встреченные.add(ключ)
        if ключ == (идентификатор_задачи, поколение):
            найденное = завершение
            объект_найденного = объект
    return найденное, ссылка, вершина, объект_найденного


def прочитать_очередь(
    корень: Path,
    ожидаемая_ветка: str,
) -> tuple[dict[str, object], str, str]:
    ссылка = ссылка_очереди(корень)
    идентификатор_объекта = прочитать_идентификатор_объекта_ссылки(
        корень,
        ссылка,
    )
    if идентификатор_объекта is None:
        raise ОшибкаКонтракта("служебная очередь рабочей копии отсутствует")
    тип = выполнить_гит_строго(
        корень,
        "проверить тип объекта очереди",
        "cat-file",
        "-t",
        идентификатор_объекта,
    ).stdout.strip()
    if тип != "blob":
        raise ОшибкаКонтракта("служебная очередь не указывает на blob")
    сырой = выполнить_гит_строго(
        корень,
        "прочитать объект очереди",
        "cat-file",
        "blob",
        идентификатор_объекта,
    ).stdout
    try:
        значение = json.loads(
            сырой,
            object_pairs_hook=собрать_объект_без_повторов,
            parse_constant=lambda константа: (_ for _ in ()).throw(
                ОшибкаКонтракта(
                    f"очередь содержит неконечную константу {константа}"
                )
            ),
        )
    except (UnicodeError, json.JSONDecodeError) as ошибка:
        raise ОшибкаКонтракта("объект очереди повреждён") from ошибка
    очередь = потребовать_объект(значение, "очередь")
    ожидаемые_поля = {
        "schema_version",
        "worktree_id",
        "branch_ref",
        "next_seq",
        "owner",
        "waiting",
        "last_completion",
        "updated_at",
    }
    if set(очередь) != ожидаемые_поля:
        raise ОшибкаКонтракта("очередь имеет неверный набор полей")
    if (
        очередь["schema_version"] != 1
        or очередь["worktree_id"] != идентичность_рабочей_копии(корень)
        or очередь["branch_ref"] != ожидаемая_ветка
    ):
        raise ОшибкаКонтракта("очередь принадлежит другому контракту")
    потребовать_целое(очередь["next_seq"], "очередь.next_seq", 1)
    владелец = очередь["owner"]
    if владелец is not None:
        проверить_участника_очереди(владелец, владелец=True)
    ожидающие = потребовать_массив(очередь["waiting"], "очередь.waiting")
    участники = (
        ([владелец] if isinstance(владелец, dict) else [])
        + [
            проверить_участника_очереди(участник, владелец=False)
            for участник in ожидающие
        ]
    )
    последовательности = [int(участник["seq"]) for участник in участники]
    идентификаторы_задач = [
        str(участник["task_id"]) for участник in участники
    ]
    билеты = [str(участник["ticket_id"]) for участник in участники]
    if (
        последовательности != sorted(последовательности)
        or len(последовательности) != len(set(последовательности))
        or len(идентификаторы_задач) != len(set(идентификаторы_задач))
        or len(билеты) != len(set(билеты))
        or (
            последовательности
            and int(очередь["next_seq"]) <= max(последовательности)
        )
    ):
        raise ОшибкаКонтракта("очередь нарушает порядок или уникальность")
    проверить_завершение_очереди(очередь["last_completion"])
    if not isinstance(очередь["updated_at"], str) or not очередь["updated_at"]:
        raise ОшибкаКонтракта("очередь не имеет метки updated_at")
    return очередь, ссылка, идентификатор_объекта


def проверить_чистоту_ограждения_запуска(корень: Path) -> None:
    индекс = выполнить_гит(
        корень,
        "diff",
        "--cached",
        "--quiet",
        "--exit-code",
        "--",
    )
    if индекс.returncode == 1:
        raise ОшибкаКонтракта("общий run-fence требует пустой Git-индекс")
    if индекс.returncode != 0:
        raise ОшибкаКонтракта("не удалось проверить Git-индекс run-fence")
    дерево = выполнить_гит_строго(
        корень,
        "проверить чистоту checkout общего run-fence",
        "-c",
        "core.quotepath=false",
        "status",
        "--porcelain=v1",
        "-z",
        "--untracked-files=all",
        "--ignore-submodules=none",
        "--",
        ".",
        ":(top,exclude).obsidian",
        ":(top,exclude).obsidian/**",
    )
    if дерево.stdout:
        raise ОшибкаКонтракта(
            "общий run-fence требует чистый checkout вне корневой .obsidian"
        )


def заменить_общее_ограждение_запуска(
    корень: Path,
    ссылка_резервации_запуска: str,
    прежний_объект: str,
    новый_объект: str | None,
    ссылка_очереди_задач: str,
    объект_очереди: str,
    ветка: str,
    вершина: str,
) -> bool:
    команда_резервации = (
        f"verify {ссылка_резервации_запуска} {прежний_объект}\n"
        if новый_объект is None
        else (
            f"update {ссылка_резервации_запуска} "
            f"{новый_объект} {прежний_объект}\n"
        )
    )
    транзакция = (
        "start\n"
        f"verify {ссылка_очереди_задач} {объект_очереди}\n"
        f"verify {ветка} {вершина}\n"
        f"{команда_резервации}"
        "prepare\n"
        "commit\n"
    )
    результат = выполнить_гит(
        корень,
        "update-ref",
        "--no-deref",
        "--stdin",
        вход=транзакция,
    )
    if результат.returncode == 0:
        return True
    if вершина_ветки(корень, ветка) != вершина:
        raise ОшибкаКонтракта("вершина ветки изменилась во время run-fence")
    if (
        прочитать_идентификатор_объекта_ссылки(
            корень,
            ссылка_очереди_задач,
        )
        != объект_очереди
        or прочитать_идентификатор_объекта_ссылки(
            корень,
            ссылка_резервации_запуска,
        )
        != прежний_объект
    ):
        return False
    подробность = результат.stderr.strip() or "Git не вернул текст ошибки"
    raise ОшибкаКонтракта(
        f"не удалось атомарно обновить общий run-fence: {подробность}"
    )


def заменить_резервацию_при_терминализации(
    корень: Path,
    ссылка_резервации_запуска: str,
    прежний_объект: str,
    новый_объект: str,
    ссылка_очереди_задач: str,
    объект_очереди: str,
    ссылка_доказательства: str,
    объект_доказательства: str,
    ветка: str,
    вершина_ветки_снимка: str,
    отсутствующая_ссылка: str | None = None,
) -> bool:
    if ссылка_доказательства == ссылка_очереди_задач:
        if объект_доказательства != объект_очереди:
            raise ОшибкаКонтракта(
                "одна ссылка очереди не может иметь два ожидаемых объекта"
            )
        проверка_доказательства = ""
    else:
        проверка_доказательства = (
            f"verify {ссылка_доказательства} {объект_доказательства}\n"
        )
    проверка_отсутствия = ""
    if отсутствующая_ссылка is not None:
        нулевой_объект = "0" * длина_идентификатора_объекта(корень)
        проверка_отсутствия = (
            f"verify {отсутствующая_ссылка} {нулевой_объект}\n"
        )
    транзакция = (
        "start\n"
        f"verify {ссылка_очереди_задач} {объект_очереди}\n"
        f"{проверка_доказательства}"
        f"{проверка_отсутствия}"
        f"verify {ветка} {вершина_ветки_снимка}\n"
        f"update {ссылка_резервации_запуска} "
        f"{новый_объект} {прежний_объект}\n"
        "prepare\n"
        "commit\n"
    )
    результат = выполнить_гит(
        корень,
        "update-ref",
        "--no-deref",
        "--stdin",
        вход=транзакция,
    )
    if результат.returncode == 0:
        return True
    if (
        вершина_ветки(корень, ветка) != вершина_ветки_снимка
        or прочитать_идентификатор_объекта_ссылки(
            корень,
            ссылка_очереди_задач,
        )
        != объект_очереди
        or (
            отсутствующая_ссылка is not None
            and прочитать_идентификатор_объекта_ссылки(
                корень,
                отсутствующая_ссылка,
            )
            is not None
        )
        or прочитать_идентификатор_объекта_ссылки(
            корень,
            ссылка_доказательства,
        )
        != объект_доказательства
        or прочитать_идентификатор_объекта_ссылки(
            корень,
            ссылка_резервации_запуска,
        )
        != прежний_объект
    ):
        return False
    подробность = результат.stderr.strip() or "Git не вернул текст ошибки"
    raise ОшибкаКонтракта(
        "не удалось атомарно терминализировать общий запуск: " + подробность
    )


def очередь_содержит_задачу(
    очередь: dict[str, object],
    идентификатор_задачи: str,
) -> bool:
    владелец = очередь["owner"]
    if (
        isinstance(владелец, dict)
        and владелец.get("task_id") == идентификатор_задачи
    ):
        return True
    return any(
        isinstance(ожидающий, dict)
        and ожидающий.get("task_id") == идентификатор_задачи
        for ожидающий in потребовать_массив(
            очередь["waiting"],
            "очередь.waiting",
        )
    )


def является_предком(
    корень: Path,
    предок: str,
    потомок: str,
) -> bool:
    результат = выполнить_гит(
        корень,
        "merge-base",
        "--is-ancestor",
        предок,
        потомок,
    )
    if результат.returncode == 0:
        return True
    if результат.returncode == 1:
        return False
    подробность = результат.stderr.strip() or "Git не вернул текст ошибки"
    raise ОшибкаКонтракта(
        "не удалось проверить достижимость завершения: " + подробность
    )


def проверить_результат_завершения(
    корень: Path,
    завершение: dict[str, object],
    ожидаемая_вершина: str,
    текущая_вершина: str,
    восстановление_адаптера: str | None,
) -> tuple[tuple[str, str, str | None] | None, str | None]:
    if завершение["kind"] == "committed":
        if завершение["base_head"] != ожидаемая_вершина:
            return None, "base_head_changed"
        итоговая_вершина = str(завершение["head"])
        тип = выполнить_гит_строго(
            корень,
            "проверить тип коммита результата",
            "cat-file",
            "-t",
            итоговая_вершина,
        ).stdout.strip()
        if тип != "commit":
            raise ОшибкаКонтракта("результат завершения не является коммитом")
        строка_родителей = выполнить_гит_строго(
            корень,
            "прочитать родителей коммита результата",
            "rev-list",
            "--parents",
            "--max-count=1",
            итоговая_вершина,
            "--",
        ).stdout.strip().split()
        if строка_родителей != [итоговая_вершина, ожидаемая_вершина]:
            return None, "result_parent_changed"
        if not является_предком(корень, итоговая_вершина, текущая_вершина):
            return None, "result_not_reachable"
        return ("успех", итоговая_вершина, итоговая_вершина), None
    if (
        завершение["head"] != ожидаемая_вершина
        or восстановление_адаптера not in {"released", "unclaimed"}
    ):
        return None, "adapter_recovery_required"
    if not является_предком(корень, ожидаемая_вершина, текущая_вершина):
        return None, "clean_head_not_reachable"
    return (
        "безопасный_отказ_до_эффекта",
        ожидаемая_вершина,
        None,
    ), None


def привязать_общий_запуск(
    корень_сырой: str,
    ожидаемая_ветка: str,
    ожидаемая_вершина: str,
    ожидаемое_задание: str,
    ожидаемое_поколение: int,
    ожидаемое_поколение_реестра: int,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
    идентификатор_задачи: str,
) -> tuple[int, dict[str, object]]:
    точный_идентификатор_задачи = проверить_оперативный_идентификатор(
        идентификатор_задачи,
        "task_id",
    )
    for _ in range(МАКСИМУМ_ПОПЫТОК_СРАВНЕНИЯ_И_ЗАМЕНЫ):
        корень, ссылка, резервация, прежний_объект = (
            загрузить_точную_резервацию_после_вызова(
                корень_сырой,
                ожидаемая_ветка,
                ожидаемое_задание,
                ожидаемый_ключ_запуска,
                идентификатор_попытки,
                ожидаемая_вершина,
                ожидаемое_поколение,
                ожидаемое_поколение_реестра,
            )
        )
        if резервация["фаза"] not in {
            "вызов_мог_состояться",
            "задача_создана",
        }:
            return ответ_несовпадения_ограждения_запуска("phase_changed")
        существующий_идентификатор_задачи = резервация["task_id"]
        if существующий_идентификатор_задачи is not None:
            if (
                существующий_идентификатор_задачи
                != точный_идентификатор_задачи
            ):
                return ответ_несовпадения_ограждения_запуска("task_changed")
            return 0, {
                "состояние": "bound",
                "владение": "существующее",
            }
        новая_резервация = dict(резервация)
        новая_резервация["task_id"] = точный_идентификатор_задачи
        новый_объект = записать_объект_резервации(
            корень,
            новая_резервация,
            ожидаемая_ветка,
            ожидаемое_задание,
        )
        if заменить_резервацию_сравнением(
            корень,
            ссылка,
            прежний_объект,
            новый_объект,
            ожидаемая_ветка,
            ожидаемая_вершина,
        ):
            return 0, {"состояние": "bound", "владение": "новое"}
    raise ОшибкаКонтракта("общий bind-run исчерпал попытки CAS")


def проверить_общий_запуск(
    корень_сырой: str,
    ожидаемая_ветка: str,
    ожидаемая_вершина: str,
    ожидаемое_задание: str,
    ожидаемое_поколение: int,
    ожидаемое_поколение_реестра: int,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
    идентификатор_задачи: str,
    поколение_очереди: str,
) -> tuple[int, dict[str, object]]:
    точный_идентификатор_задачи = проверить_оперативный_идентификатор(
        идентификатор_задачи,
        "task_id",
    )
    точное_поколение = проверить_оперативный_идентификатор(
        поколение_очереди,
        "generation",
    )
    for _ in range(МАКСИМУМ_ПОПЫТОК_СРАВНЕНИЯ_И_ЗАМЕНЫ):
        корень, ссылка, резервация, прежний_объект = (
            загрузить_точную_резервацию_после_вызова(
                корень_сырой,
                ожидаемая_ветка,
                ожидаемое_задание,
                ожидаемый_ключ_запуска,
                идентификатор_попытки,
                ожидаемая_вершина,
                ожидаемое_поколение,
                ожидаемое_поколение_реестра,
            )
        )
        if резервация["task_id"] != точный_идентификатор_задачи:
            return ответ_несовпадения_ограждения_запуска("task_changed")
        if резервация["фаза"] not in {
            "вызов_мог_состояться",
            "задача_создана",
        }:
            return ответ_несовпадения_ограждения_запуска("phase_changed")
        очередь, ссылка_очереди_задач, объект_очереди = прочитать_очередь(
            корень,
            ожидаемая_ветка,
        )
        владелец = очередь["owner"]
        if not isinstance(владелец, dict) or (
            владелец["task_id"] != точный_идентификатор_задачи
            or владелец["generation"] != точное_поколение
            or владелец["base_head"] != ожидаемая_вершина
        ):
            return ответ_несовпадения_ограждения_запуска("not_owner")
        проверить_чистоту_ограждения_запуска(корень)
        новый_объект: str | None = None
        if резервация["generation"] is None:
            новая_резервация = dict(резервация)
            новая_резервация["generation"] = точное_поколение
            новый_объект = записать_объект_резервации(
                корень,
                новая_резервация,
                ожидаемая_ветка,
                ожидаемое_задание,
            )
        elif резервация["generation"] != точное_поколение:
            return ответ_несовпадения_ограждения_запуска(
                "generation_changed"
            )
        проверить_чистоту_ограждения_запуска(корень)
        if заменить_общее_ограждение_запуска(
            корень,
            ссылка,
            прежний_объект,
            новый_объект,
            ссылка_очереди_задач,
            объект_очереди,
            ожидаемая_ветка,
            ожидаемая_вершина,
        ):
            return 0, {"состояние": "verified"}
    raise ОшибкаКонтракта("общий verify-run исчерпал попытки CAS")


def подтвердить_завершение_исполнителя(
    корень_сырой: str,
    ожидаемая_ветка: str,
    ожидаемая_вершина: str,
    ожидаемое_задание: str,
    ожидаемое_поколение: int,
    ожидаемое_поколение_реестра: int,
    ожидаемый_ключ_запуска: str,
    идентификатор_попытки: str,
    восстановление_адаптера: str | None,
) -> tuple[int, dict[str, object]]:
    for _ in range(МАКСИМУМ_ПОПЫТОК_СРАВНЕНИЯ_И_ЗАМЕНЫ):
        корень, ссылка, резервация, прежний_объект = (
            загрузить_точную_резервацию_после_вызова(
                корень_сырой,
                ожидаемая_ветка,
                ожидаемое_задание,
                ожидаемый_ключ_запуска,
                идентификатор_попытки,
                ожидаемая_вершина,
                ожидаемое_поколение,
                ожидаемое_поколение_реестра,
            )
        )
        if резервация["фаза"] == "завершён":
            return 0, {
                "состояние": "завершён",
                "исход": резервация["исход"],
                "владение": "существующее",
            }
        идентификатор_задачи = резервация["task_id"]
        поколение_очереди = резервация["generation"]
        if идентификатор_задачи is None or поколение_очереди is None:
            return ответ_несовпадения_ограждения_запуска("unverified")
        очередь, ссылка_очереди_задач, объект_очереди = прочитать_очередь(
            корень,
            ожидаемая_ветка,
        )
        if очередь_содержит_задачу(очередь, идентификатор_задачи):
            return ответ_несовпадения_ограждения_запуска("queue_busy")
        (
            завершение,
            ссылка_журнала,
            объект_журнала,
            _объект_завершения,
        ) = найти_завершение_в_журнале(
            корень,
            ожидаемая_ветка,
            идентификатор_задачи,
            поколение_очереди,
        )
        if объект_журнала is None:
            текущее_завершение = проверить_завершение_очереди(
                очередь["last_completion"]
            )
            if текущее_завершение is not None and (
                текущее_завершение["task_id"] == идентификатор_задачи
                and текущее_завершение["generation"] == поколение_очереди
            ):
                завершение = текущее_завершение
                ссылка_доказательства = ссылка_очереди_задач
                объект_доказательства = объект_очереди
                отсутствующая_ссылка = ссылка_журнала
            else:
                return ответ_несовпадения_ограждения_запуска(
                    "completion_changed"
                )
        else:
            if завершение is None:
                return ответ_несовпадения_ограждения_запуска(
                    "completion_changed"
                )
            ссылка_доказательства = ссылка_журнала
            объект_доказательства = объект_журнала
            отсутствующая_ссылка = None
        текущая_вершина = вершина_ветки(корень, ожидаемая_ветка)
        результат_проверки, причина = проверить_результат_завершения(
            корень,
            завершение,
            ожидаемая_вершина,
            текущая_вершина,
            восстановление_адаптера,
        )
        if результат_проверки is None:
            if причина is None:
                raise ОшибкаКонтракта(
                    "проверка результата не вернула причину отказа"
                )
            return ответ_несовпадения_ограждения_запуска(причина)
        исход, итоговая_вершина, подтверждение = результат_проверки
        новая_резервация = dict(резервация)
        новая_резервация["подтверждение_результата"] = подтверждение
        новая_резервация["фаза"] = "завершён"
        новая_резервация["исход"] = исход
        новый_объект = записать_объект_резервации(
            корень,
            новая_резервация,
            ожидаемая_ветка,
            ожидаемое_задание,
        )
        if заменить_резервацию_при_терминализации(
            корень,
            ссылка,
            прежний_объект,
            новый_объект,
            ссылка_очереди_задач,
            объект_очереди,
            ссылка_доказательства,
            объект_доказательства,
            ожидаемая_ветка,
            текущая_вершина,
            отсутствующая_ссылка,
        ):
            return 0, {
                "состояние": "завершён",
                "исход": исход,
                "владение": "новое",
            }
    raise ОшибкаКонтракта("терминализация общего запуска исчерпала попытки CAS")


def ссылка_управления(корень: Path, ветка: str) -> str:
    хэш_ветки = hashlib.sha256(ветка.encode("utf-8")).hexdigest()
    return (
        f"{ПРОСТРАНСТВО_УПРАВЛЕНИЯ_ДИСПЕТЧЕРОМ}/"
        f"{идентичность_рабочей_копии(корень)}/{хэш_ветки}"
    )


def проверить_ограждение_управления(
    значение: object,
    ожидаемая_ветка: str,
) -> dict[str, object]:
    ограждение = потребовать_объект(значение, "ограждение управления")
    проверить_поля(
        ограждение,
        ПОЛЯ_ОГРАЖДЕНИЯ_УПРАВЛЕНИЯ,
        "ограждение управления",
    )
    if ограждение["версия_схемы"] != 1:
        raise ОшибкаКонтракта("ограждение управления имеет неверную схему")
    if ограждение["branch_ref"] != ожидаемая_ветка:
        raise ОшибкаКонтракта("ограждение управления относится к другой ветке")
    проверить_ссылку_ветки(ограждение["branch_ref"], "ограждение.branch_ref")
    вершина = ограждение["selection_head"]
    if (
        not isinstance(вершина, str)
        or ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(вершина) is None
    ):
        raise ОшибкаКонтракта("ограждение управления имеет неверную вершину")
    потребовать_строку(
        ограждение["идентификатор_реестра"],
        "ограждение.идентификатор_реестра",
    )
    потребовать_целое(
        ограждение["поколение_реестра"],
        "ограждение.поколение_реестра",
        1,
    )
    for поле in (
        "хэш_реестра",
        "идентификатор_предложения",
        "хэш_сообщения",
    ):
        проверить_криптографический_хэш(
            ограждение[поле],
            f"ограждение.{поле}",
        )
    for поле in ("идентификатор_сообщения", "task_id", "generation"):
        проверить_оперативный_идентификатор(
            ограждение[поле],
            f"ограждение.{поле}",
        )
    return ограждение


def прочитать_ограждение_управления(
    корень: Path,
    ветка: str,
) -> tuple[dict[str, object] | None, str | None, str]:
    ссылка = ссылка_управления(корень, ветка)
    идентификатор_объекта = прочитать_идентификатор_объекта_ссылки(
        корень,
        ссылка,
    )
    if идентификатор_объекта is None:
        return None, None, ссылка
    тип = выполнить_гит_строго(
        корень,
        "проверить тип объекта ограждения управления",
        "cat-file",
        "-t",
        идентификатор_объекта,
    ).stdout.strip()
    if тип != "blob":
        raise ОшибкаКонтракта(
            "служебная ссылка управления не указывает на blob"
        )
    сырой = выполнить_гит_строго(
        корень,
        "прочитать ограждение управления",
        "cat-file",
        "blob",
        идентификатор_объекта,
    ).stdout
    try:
        значение = json.loads(
            сырой,
            object_pairs_hook=собрать_объект_без_повторов,
        )
    except (UnicodeError, json.JSONDecodeError) as ошибка:
        raise ОшибкаКонтракта("ограждение управления повреждено") from ошибка
    ограждение = проверить_ограждение_управления(значение, ветка)
    if сырой != канонический_текст_резервации(ограждение):
        raise ОшибкаКонтракта(
            "ограждение управления имеет неканонические байты"
        )
    return ограждение, идентификатор_объекта, ссылка


def записать_объект_ограждения_управления(
    корень: Path,
    ограждение: dict[str, object],
    ветка: str,
) -> str:
    проверить_ограждение_управления(ограждение, ветка)
    результат = выполнить_гит_строго(
        корень,
        "записать объект ограждения управления",
        "hash-object",
        "-w",
        "--stdin",
        вход=канонический_текст_резервации(ограждение),
    )
    идентификатор_объекта = результат.stdout.strip()
    if ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(идентификатор_объекта) is None:
        raise ОшибкаКонтракта(
            "Git не вернул объект ограждения управления"
        )
    return идентификатор_объекта


def ограждение_совпадает_с_владельцем(
    ограждение: dict[str, object] | None,
    очередь: dict[str, object],
    текущая_вершина: str,
) -> bool:
    if ограждение is None:
        return False
    владелец = очередь.get("owner")
    return isinstance(владелец, dict) and (
        ограждение["task_id"] == владелец.get("task_id")
        and ограждение["generation"] == владелец.get("generation")
        and ограждение["selection_head"] == владелец.get("base_head")
        and ограждение["selection_head"] == текущая_вершина
    )


def состояние_управления(
    корень_сырой: str,
    ожидаемая_ветка: str,
) -> dict[str, object]:
    корень = проверить_корень_рабочей_копии(корень_сырой)
    ветка = проверить_ссылку_ветки(
        ожидаемая_ветка,
        "expected-branch-ref",
    )
    состояние, _, _ = снимок_состояния_управления(корень, ветка)
    return {"состояние": состояние}


def снимок_ограждения_чистого_завершения(
    корень_сырой: str,
    ожидаемая_ветка: str,
) -> dict[str, object]:
    """Вернуть внутренний CAS-снимок без идентичности владельца."""
    корень = проверить_корень_рабочей_копии(корень_сырой)
    ветка = проверить_ссылку_ветки(
        ожидаемая_ветка,
        "expected-branch-ref",
    )
    состояние, объект, ссылка = снимок_состояния_управления(корень, ветка)
    if состояние != "inactive":
        return {"состояние": состояние}
    return {
        "состояние": "inactive",
        "ограждающая_ссылка": ссылка,
        "ожидаемый_объект_ограждения": объект or "absent",
    }


def снимок_состояния_управления(
    корень: Path,
    ветка: str,
) -> tuple[str, str | None, str]:
    """Прочитать состояние и объект fence одним согласованным снимком."""
    ограждение, объект, ссылка = прочитать_ограждение_управления(
        корень,
        ветка,
    )
    if ограждение is None:
        return "inactive", объект, ссылка
    очередь, _, _ = прочитать_очередь(корень, ветка)
    текущая_вершина = вершина_ветки(корень, ветка)
    состояние = (
        "active"
        if ограждение_совпадает_с_владельцем(
            ограждение,
            очередь,
            текущая_вершина,
        )
        else "inactive"
    )
    return состояние, объект, ссылка


def проверить_владельца_управления(
    корень: Path,
    ветка: str,
    вершина: str,
    идентификатор_задачи: str,
    поколение_очереди: str,
) -> tuple[dict[str, object], str, str] | None:
    очередь, ссылка_очереди_задач, объект_очереди = прочитать_очередь(
        корень,
        ветка,
    )
    владелец = очередь.get("owner")
    if not isinstance(владелец, dict) or (
        владелец.get("task_id") != идентификатор_задачи
        or владелец.get("generation") != поколение_очереди
        or владелец.get("base_head") != вершина
    ):
        return None
    if вершина_ветки(корень, ветка) != вершина:
        return None
    return очередь, ссылка_очереди_задач, объект_очереди


def команда_проверки_служебной_ссылки(
    ссылка: str,
    идентификатор_объекта: str | None,
    длина_объекта: int,
) -> str:
    ожидаемый = идентификатор_объекта or ("0" * длина_объекта)
    return f"verify {ссылка} {ожидаемый}\n"


def снимок_резерваций_для_управления(
    корень: Path,
    реестр: dict[str, object],
    вершина: str,
    блокировать_после_границы_среды: bool,
) -> tuple[bool, str]:
    проверки: list[str] = []
    ветка = str(реестр["branch_ref"])
    for сырое_задание in потребовать_массив(
        реестр["задания"],
        "реестр.задания",
    ):
        задание = потребовать_объект(сырое_задание, "реестр.задание")
        идентификатор_задания = потребовать_строку(
            задание["job_id"],
            "задание.job_id",
        )
        ссылка = ссылка_резервации(
            корень,
            ветка,
            идентификатор_задания,
        )
        резервация, объект = прочитать_резервацию(
            корень,
            ссылка,
            ветка,
            идентификатор_задания,
        )
        if (
            блокировать_после_границы_среды
            and резервация is not None
            and резервация["фаза"]
            in {"вызов_мог_состояться", "задача_создана"}
        ):
            return False, ""
        проверки.append(
            команда_проверки_служебной_ссылки(
                ссылка,
                объект,
                len(вершина),
            )
        )
    return True, "".join(проверки)


def начать_управление(
    корень_сырой: str,
    путь_реестра: str,
    предложение: dict[str, object],
    идентификатор_задачи: str,
    поколение_очереди: str,
) -> tuple[int, dict[str, object]]:
    корень = проверить_корень_рабочей_копии(корень_сырой)
    проверенное = проверить_предложение(предложение)
    точный_идентификатор_задачи = проверить_оперативный_идентификатор(
        идентификатор_задачи,
        "task_id",
    )
    точное_поколение = проверить_оперативный_идентификатор(
        поколение_очереди,
        "generation",
    )
    реестр = проверить_реестр(
        прочитать_данные(путь_реестра, "реестр"),
        корень,
    )
    ветка = проверить_ссылку_ветки(реестр["branch_ref"], "реестр.branch_ref")
    вершина = str(проверенное["ожидаемая_вершина"])
    if (
        реестр["поколение_реестра"]
        != проверенное["ожидаемое_поколение_реестра"]
        or хэш_реестра(реестр) != проверенное["ожидаемый_хэш_реестра"]
    ):
        return 5, {"состояние": "mismatch"}
    try:
        проверенная_вершина = проверить_авторитетный_реестр(
            корень,
            путь_реестра,
            ветка,
            реестр,
        )
    except ОшибкаКонтракта:
        return 5, {"состояние": "mismatch"}
    if проверенная_вершина != вершина:
        return 5, {"состояние": "mismatch"}
    владелец = проверить_владельца_управления(
        корень,
        ветка,
        вершина,
        точный_идентификатор_задачи,
        точное_поколение,
    )
    if владелец is None:
        return 5, {"состояние": "mismatch"}
    очередь, ссылка_очереди_задач, объект_очереди = владелец
    допускается, проверки_резерваций = снимок_резерваций_для_управления(
        корень,
        реестр,
        вершина,
        проверенное["область"] == "реестр",
    )
    if not допускается:
        return 5, {"состояние": "mismatch"}
    прежнее, прежний_объект, ссылка = прочитать_ограждение_управления(
        корень,
        ветка,
    )
    if ограждение_совпадает_с_владельцем(прежнее, очередь, вершина):
        if прежнее is not None and (
            прежнее["идентификатор_предложения"]
            == проверенное["идентификатор_предложения"]
            and прежнее["хэш_сообщения"] == проверенное["хэш_сообщения"]
        ):
            return 0, {"состояние": "active"}
        return 5, {"состояние": "mismatch"}
    проверить_чистоту_ограждения_запуска(корень)
    новое_ограждение: dict[str, object] = {
        "версия_схемы": 1,
        "branch_ref": ветка,
        "selection_head": вершина,
        "идентификатор_реестра": реестр["идентификатор_реестра"],
        "поколение_реестра": реестр["поколение_реестра"],
        "хэш_реестра": хэш_реестра(реестр),
        "идентификатор_предложения": проверенное[
            "идентификатор_предложения"
        ],
        "идентификатор_сообщения": проверенное[
            "идентификатор_сообщения"
        ],
        "хэш_сообщения": проверенное["хэш_сообщения"],
        "task_id": точный_идентификатор_задачи,
        "generation": точное_поколение,
    }
    новый_объект = записать_объект_ограждения_управления(
        корень,
        новое_ограждение,
        ветка,
    )
    команда = (
        f"create {ссылка} {новый_объект}\n"
        if прежний_объект is None
        else f"update {ссылка} {новый_объект} {прежний_объект}\n"
    )
    транзакция = (
        "start\n"
        f"verify {ссылка_очереди_задач} {объект_очереди}\n"
        f"verify {ветка} {вершина}\n"
        f"{проверки_резерваций}"
        f"{команда}"
        "prepare\n"
        "commit\n"
    )
    результат = выполнить_гит(
        корень,
        "update-ref",
        "--no-deref",
        "--stdin",
        вход=транзакция,
    )
    if результат.returncode != 0:
        return 5, {"состояние": "mismatch"}
    return 0, {"состояние": "active"}


def проверить_точное_ограждение_управления(
    корень: Path,
    ветка: str,
    предложение: dict[str, object],
    идентификатор_задачи: str,
    поколение_очереди: str,
) -> str | None:
    вершина = str(предложение["ожидаемая_вершина"])
    владелец = проверить_владельца_управления(
        корень,
        ветка,
        вершина,
        идентификатор_задачи,
        поколение_очереди,
    )
    if владелец is None:
        return None
    очередь, _, _ = владелец
    ограждение, объект, _ = прочитать_ограждение_управления(корень, ветка)
    совпадает = bool(
        ограждение_совпадает_с_владельцем(ограждение, очередь, вершина)
        and ограждение is not None
        and ограждение["идентификатор_предложения"]
        == предложение["идентификатор_предложения"]
        and ограждение["хэш_сообщения"] == предложение["хэш_сообщения"]
        and ограждение["поколение_реестра"]
        == предложение["ожидаемое_поколение_реестра"]
        and ограждение["хэш_реестра"]
        == предложение["ожидаемый_хэш_реестра"]
    )
    return объект if совпадает else None


def записать_реестр_атомарно(
    путь: Path,
    реестр: dict[str, object],
    ожидаемые_исходные_байты: bytes,
) -> None:
    if путь.read_bytes() != ожидаемые_исходные_байты:
        raise ОшибкаКонтракта("исходные байты реестра изменились")
    байты = канонический_текст(реестр).encode("utf-8")
    режим = путь.stat().st_mode & 0o777
    временное_имя: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="wb",
            dir=путь.parent,
            prefix=f".{путь.name}.",
            delete=False,
        ) as временный:
            временное_имя = временный.name
            временный.write(байты)
            временный.flush()
            os.fsync(временный.fileno())
        os.chmod(временное_имя, режим)
        if путь.read_bytes() != ожидаемые_исходные_байты:
            raise ОшибкаКонтракта("исходные байты реестра изменились")
        os.replace(временное_имя, путь)
        временное_имя = None
    finally:
        if временное_имя is not None:
            try:
                os.unlink(временное_имя)
            except FileNotFoundError:
                pass
    if путь.read_bytes() != байты:
        raise ОшибкаКонтракта("readback реестра не совпал с записью")


def применить_предложение_к_файлу(
    корень_сырой: str,
    путь_реестра: str,
    предложение: dict[str, object],
    идентификатор_задачи: str,
    поколение_очереди: str,
    подтверждения: set[str],
) -> tuple[int, dict[str, object]]:
    корень = проверить_корень_рабочей_копии(корень_сырой)
    проверенное = проверить_предложение(предложение)
    точный_идентификатор_задачи = проверить_оперативный_идентификатор(
        идентификатор_задачи,
        "task_id",
    )
    точное_поколение = проверить_оперативный_идентификатор(
        поколение_очереди,
        "generation",
    )
    ветка = проверить_ссылку_ветки(
        потребовать_объект(
            проверенное["реестр_после"],
            "предложение.реестр_после",
        )["branch_ref"],
        "предложение.branch_ref",
    )
    исходный_объект_ограждения = проверить_точное_ограждение_управления(
        корень,
        ветка,
        проверенное,
        точный_идентификатор_задачи,
        точное_поколение,
    )
    if исходный_объект_ограждения is None:
        return 5, {"состояние": "mismatch"}
    текущий = проверить_реестр(
        прочитать_данные(путь_реестра, "реестр"),
        корень,
    )
    состояние, новый_реестр = применить_предложение_к_реестру(
        текущий,
        проверенное,
        подтверждения,
    )
    if состояние in {"конфликт_поколения", "требуется_подтверждение"}:
        return 5, {"состояние": состояние}
    if состояние == "требуется_изменение_host":
        return 3, {"состояние": состояние}
    if состояние == "уже_применено":
        return 0, {"состояние": состояние}
    if состояние != "применено":
        return 5, {"состояние": состояние}
    try:
        вершина = проверить_авторитетный_реестр(
            корень,
            путь_реестра,
            ветка,
            текущий,
        )
    except ОшибкаКонтракта:
        return 5, {"состояние": "конфликт_поколения"}
    if вершина != проверенное["ожидаемая_вершина"]:
        return 5, {"состояние": "mismatch"}
    текущий_объект_ограждения = проверить_точное_ограждение_управления(
        корень,
        ветка,
        проверенное,
        точный_идентификатор_задачи,
        точное_поколение,
    )
    if текущий_объект_ограждения != исходный_объект_ограждения:
        return 5, {"состояние": "mismatch"}
    разрешённый_путь_реестра = Path(путь_реестра).resolve()
    исходные_байты = канонический_текст(текущий).encode("utf-8")
    записать_реестр_атомарно(
        разрешённый_путь_реестра,
        новый_реестр,
        исходные_байты,
    )
    итоговый_объект_ограждения = проверить_точное_ограждение_управления(
        корень,
        ветка,
        проверенное,
        точный_идентификатор_задачи,
        точное_поколение,
    )
    if итоговый_объект_ограждения != исходный_объект_ограждения:
        raise ОшибкаКонтракта(
            "ограждение управления изменилось во время записи реестра"
        )
    return 0, {"состояние": "применено"}


def состояние_общей_резервации(
    корень_сырой: str,
    ожидаемая_ветка: str,
    ожидаемое_задание: str,
) -> dict[str, object]:
    корень = проверить_корень_рабочей_копии(корень_сырой)
    проверить_ссылку_ветки(ожидаемая_ветка, "expected-branch-ref")

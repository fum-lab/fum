#!/usr/bin/env python3
"""Адресный профиль двух синтетических заголовков; сеть и реальные ответы не используются."""
import sys
sys.dont_write_bytecode = True
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform

КОРЕНЬ = Path(__file__).resolve().parents[3]
ПОВТОРЫ = 7
ПАКЕТ = 1000
СТАДИИ = ("Очистка сырых синтетических заголовков", "Повторная очистка ожидаемых заголовков")
КОД = (
    "Инструменты/fum-materialyi-zaprosov/scripts/source_archive.py",
    "Инструменты/fum-materialyi-zaprosov/tests/профиль_очистки_заголовков.py",
    "Инструменты/fum-snimki-indeksa/scripts/профиль.py",
)


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def прочитать_код():
    снимок = {}
    for имя in КОД:
        путь = КОРЕНЬ / имя
        if (путь.resolve(strict=True) != путь or not путь.is_file()
                or any(часть.is_symlink() for часть in (путь, *путь.parents))):
            raise ValueError("Нужны физические обычные файлы кода")
        снимок[имя] = хэш(путь.read_bytes())
    return снимок


def создать_фикстуры():
    соседи = (
        "Content-Type: text/html; charset=utf-8\r\n"
        "Content-Language: ru\r\n"
        "Last-Modified: Mon, 07 Sep 2026 12:00:00 GMT\r\n"
        "X-Served-By-Example: public-example-node\r\n"
        "X-GitHub-Edge-Region-Example: public-example-region\r\n"
        "X-Public-Note: public-value\r\n"
        " public-folded-space\r\n"
        "\tpublic-folded-tab\r\n"
    )
    набор = []
    for имя in ("X-Served-By", "X-GitHub-Edge-Region"):
        сырьё = (
            "HTTP/2 200\r\n"
            f"{имя.swapcase()}: synthetic-private-first-a, synthetic-private-first-b\r\n"
            " synthetic-private-folded-space\r\n"
            "\tsynthetic-private-folded-tab\r\n"
            f"{имя.upper()}: synthetic-private-second-a, synthetic-private-second-b\r\n"
            + соседи
        )
        ожидание = "HTTP/2 200\r\n" + f"{имя.lower()}: [REDACTED: request metadata]\n" * 2 + соседи
        набор.append((имя, сырьё, ожидание))
    return набор


def описать_фикстуры(набор):
    return [{"имя": имя, "вход_байт": len(сырьё.encode("utf-8")),
             "вход_хэш": хэш(сырьё.encode("utf-8")),
             "ожидание_байт": len(ожидание.encode("utf-8")),
             "ожидание_хэш": хэш(ожидание.encode("utf-8"))}
            for имя, сырьё, ожидание in набор]


def наблюдать(архив, набор):
    сырые_выходы = [архив.redact_headers(сырьё) for имя, сырьё, ожидание in набор]
    ожидаемые_выходы = [архив.redact_headers(ожидание) for имя, сырьё, ожидание in набор]
    состояние = {
        "корректная_очистка": all(выход == ожидание for выход, (имя, сырьё, ожидание)
                                 in zip(сырые_выходы, набор)),
        "идемпотентность": all(архив.redact_headers(выход) == выход for выход in сырые_выходы)
            and all(выход == ожидание for выход, (имя, сырьё, ожидание)
                    in zip(ожидаемые_выходы, набор)),
        "хэши_выходов_сырья": [хэш(выход.encode("utf-8")) for выход in сырые_выходы],
        "хэши_выходов_ожиданий": [хэш(выход.encode("utf-8")) for выход in ожидаемые_выходы],
    }
    return состояние, сырые_выходы, ожидаемые_выходы


def проверить_выход(путь):
    if (not путь.is_absolute() or путь.parent.resolve(strict=True) != путь.parent
            or any(часть.is_symlink() for часть in путь.parents)
            or путь.is_relative_to(КОРЕНЬ) or os.path.lexists(путь)):
        raise ValueError("Нужен новый явный физический абсолютный выход вне checkout")
    return путь


def выполнить(фаза, выход):
    код_до = прочитать_код()
    набор = создать_фикстуры()
    фикстуры_до = описать_фикстуры(набор)
    sys.path.insert(0, str(КОРЕНЬ / "Инструменты/fum-materialyi-zaprosov/scripts"))
    import source_archive as архив
    sys.path.insert(0, str(КОРЕНЬ / "Инструменты/fum-snimki-indeksa/scripts"))
    from профиль import Профиль
    if (Path(архив.__file__).resolve() != КОРЕНЬ / КОД[0]
            or Path(sys.modules[Профиль.__module__].__file__).resolve() != КОРЕНЬ / КОД[2]
            or прочитать_код() != код_до):
        raise ValueError("Изменились исполняемые входы профиля")
    проверка_до, сырые_до, ожидаемые_до = наблюдать(архив, набор)
    if фаза == "после" and not (проверка_до["корректная_очистка"] and проверка_до["идемпотентность"]):
        raise ValueError("После ремонта не достигнуты независимое ожидание и идемпотентность")
    профиль = Профиль()
    сырые_последние = [None] * len(набор)
    ожидаемые_последние = [None] * len(набор)
    for повтор in range(ПОВТОРЫ):
        with профиль.стадия(СТАДИИ[0]):
            for номер, (имя, сырьё, ожидание) in enumerate(набор):
                for вызов in range(ПАКЕТ):
                    сырые_последние[номер] = архив.redact_headers(сырьё)
        профиль.учесть("вызовов_сырья", ПАКЕТ * len(набор))
        with профиль.стадия(СТАДИИ[1]):
            for номер, (имя, сырьё, ожидание) in enumerate(набор):
                for вызов in range(ПАКЕТ):
                    ожидаемые_последние[номер] = архив.redact_headers(ожидание)
        профиль.учесть("вызовов_ожиданий", ПАКЕТ * len(набор))
    проверка_после, сырые_после, ожидаемые_после = наблюдать(архив, набор)
    набор_после = создать_фикстуры()
    фикстуры_после = описать_фикстуры(набор_после)
    код_после = прочитать_код()
    if (код_после != код_до or набор_после != набор or фикстуры_после != фикстуры_до
            or проверка_после != проверка_до or сырые_последние != сырые_до
            or ожидаемые_последние != ожидаемые_до or сырые_после != сырые_до
            or ожидаемые_после != ожидаемые_до):
        raise ValueError("Входы или наблюдаемое поведение изменились во время профиля")
    if фаза == "после" and not (проверка_после["корректная_очистка"] and проверка_после["идемпотентность"]):
        raise ValueError("После измерений не подтверждена исправленная очистка")
    счётчики = {"повторы": ПОВТОРЫ, "фикстур": len(набор), "стадий": len(профиль.записи),
                "вызовов_на_фикстуру_в_стадии": ПАКЕТ, **профиль.счётчики}
    счётчики["вызовов_измерено"] = счётчики["вызовов_сырья"] + счётчики["вызовов_ожиданий"]
    отчёт = {"схема": "fum.профиль-очистки-заголовков.1", "фаза": фаза,
             "версия_Питона": platform.python_version(), "хэширование": "SHA256",
             "код_до": код_до, "код_после": код_после,
             "фикстуры_до": фикстуры_до, "фикстуры_после": фикстуры_после,
             "проверка_до": проверка_до, "проверка_после": проверка_после,
             "счётчики": счётчики, "измерения": профиль.записи,
             "границы": "Синтетические строки в памяти: измеряются вызовы redact_headers, цикл и присваивание последнего результата. Подготовка, импорты, хэширование, чтение кода, проверки и сохранение вне таймера; сеть, реальные ответы, HTML и старт Python не измеряются. Исход успех общей стадии означает завершение вызовов, а не успешную очистку; её отражает отдельное поле корректная_очистка. Три хэша кода не заявляют полный байтовый охват среды Python или транзитивных импортов."}
    данные = (json.dumps(отчёт, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")
    дескриптор = os.open(выход, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    os.fchmod(дескриптор, 0o600)
    with os.fdopen(дескриптор, "wb") as поток:
        поток.write(данные)
    прочитано = выход.read_bytes()
    код_после_чтения = прочитать_код()
    if (прочитано != данные or json.loads(прочитано) != отчёт
            or код_после_чтения != код_до
            or описать_фикстуры(создать_фикстуры()) != фикстуры_до):
        raise ValueError("Не подтверждено точное обратное чтение результата и входов")
    print(json.dumps({"схема": "fum.чтение-профиля-заголовков.1", "фаза": фаза,
        "прочитано_обратно": True, "хэш_результата": хэш(прочитано), "байт_результата": len(прочитано),
        "код_после_чтения": код_после_чтения, "счётчики": счётчики}, ensure_ascii=False, sort_keys=True))


def главный():
    парсер = argparse.ArgumentParser(prog="профиль-очистки-заголовков", description=__doc__)
    парсер.add_argument("--выход", type=Path, required=True)
    парсер.add_argument("--фаза", choices=("до", "после"), required=True)
    параметры = парсер.parse_args()
    try:
        выход = проверить_выход(параметры.выход)
        выполнить(параметры.фаза, выход)
    except Exception as ошибка:
        print("Профиль не завершён: " + type(ошибка).__name__, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(главный())

def _процесс(папка, манифест, исходники, число_обращений, повторы):
    папка.mkdir(mode=0o700)
    команда = [sys.executable, '-I', '-S', '-B', '-c', дочерний_код, str(каталог), str(манифест),
               hashlib.sha256(_байты(исходники)).hexdigest(), str(число_обращений), str(повторы)]
    вызов = {'аргументы': команда, 'cwd': str(каталог), 'тайм_аут_секунд': 120}
    with (папка / 'вызов.json').open('xb') as файл: файл.write(_байты(вызов))
    начало = time.monotonic_ns(); номер_процесса = None; код = None; полнота = False
    состояние = 'не запущен'; ошибка = None
    try:
        with (папка / 'stdout.bin').open('xb') as вывод, (папка / 'stderr.bin').open('xb') as ошибки:
            процесс = subprocess.Popen(команда, cwd=каталог, stdout=вывод, stderr=ошибки)
            номер_процесса = процесс.pid; состояние = 'не завершён'
            try:
                код = процесс.wait(timeout=120); полнота = True; состояние = 'завершён'
            except subprocess.TimeoutExpired as исключение:
                ошибка = type(исключение).__name__
                процесс.kill(); код = процесс.wait(timeout=10)
    except (OSError, subprocess.SubprocessError) as исключение:
        ошибка = type(исключение).__name__
    finally:
        длительность = time.monotonic_ns() - начало
        результат = {'метка': папка.name, 'номер_процесса': номер_процесса, 'код': код, 'полнота_вывода': полнота,
                     'состояние': состояние, 'ошибка': ошибка, 'монотонные_нс': длительность,
                     'вызов_sha256': hashlib.sha256(_байты(вызов)).hexdigest(), 'каналы': {}}
        удержанные_каналы = {}
        for канал in ('stdout', 'stderr'):
            путь = папка / (канал + '.bin')
            if путь.is_file():
                исходные = путь.read_bytes(); удержанные_каналы[канал] = исходные
                результат['каналы'][канал] = {'sha256': hashlib.sha256(исходные).hexdigest(), 'байты': len(исходные)}
            else:
                результат['каналы'][канал] = {'sha256': None, 'байты': None}
        with (папка / 'исход.json').open('xb') as файл: файл.write(_байты(результат))
    if код != 0 or not полнота:
        raise ValueError('Процесс профиля не завершился успешно; RAW сохранён')
    результат['профиль'] = json.loads(удержанные_каналы['stdout'])
    return результат


def _сверить_вывод(папка, процесс):
    сохранённый = json.loads((папка / 'исход.json').read_bytes())
    if сохранённый != {к: в for к, в in процесс.items() if к != 'профиль'}:
        raise ValueError('Изменилось свидетельство процесса')
    if hashlib.sha256((папка / 'вызов.json').read_bytes()).hexdigest() != процесс['вызов_sha256']:
        raise ValueError('Изменились аргументы процесса')
    удержанные = {}
    for канал in ('stdout', 'stderr'):
        удержанные[канал] = (папка / (канал + '.bin')).read_bytes()
        if {'sha256': hashlib.sha256(удержанные[канал]).hexdigest(), 'байты': len(удержанные[канал])} != процесс['каналы'][канал]:
            raise ValueError('Изменился полный RAW процесса')
    if _байты(процесс['профиль']) != удержанные['stdout']:
        raise ValueError('Профиль не соответствует полному RAW')


def измерить_серию(каталог_вывода, *, число_обращений=64, повторы=3):
    папка = Path(каталог_вывода)
    if not папка.is_absolute() or папка != папка.resolve() or any(п.is_symlink() or (п / '.git').exists() for п in (папка, *папка.parents)):
        raise ValueError('RAW требует нового физического каталога вне Git')
    исходники = снимок_исходников(); папка.mkdir(mode=0o700)
    манифест = папка / 'исходники.json'
    with манифест.open('xb') as файл: файл.write(_байты(исходники))
    манифест.chmod(0o400); процессы = []; входы = None
    for номер in range(1, 4):
        _сверить_исходники(исходники)
        процесс = _процесс(папка / f'процесс-{номер}', манифест, исходники, число_обращений, повторы)
        _сверить_исходники(исходники)
        _сверить_вывод(папка / процесс['метка'], процесс)
        профиль = процесс['профиль']
        if (процесс['код'] != 0 or процесс['полнота_вывода'] is not True
                or профиль['схема'] != 'fum.профиль-внимания-к-обсуждениям.2'
                or профиль['номер_процесса'] != процесс['номер_процесса'] or процесс['номер_процесса'] == os.getpid()
                or процесс['номер_процесса'] in {п['номер_процесса'] for п in процессы}
                or профиль['источники_до'] != исходники or профиль['источники_после'] != исходники
                or профиль['хэш_исполненного_профиля'] != исходники[имена_исходников[0]]['sha256']
                or профиль['число_обращений'] != число_обращений or профиль['повторы'] != повторы):
            raise ValueError('Не подтверждены PID, параметры или исполненные источники')
        текущие = [с['вход_sha256'] for с in профиль['сценарии']]
        if входы is not None and входы != текущие:
            raise ValueError('Входы процессов различаются')
        входы = текущие; процессы.append(процесс)
    _сверить_исходники(исходники)
    if манифест.read_bytes() != _байты(исходники):
        raise ValueError('Изменился заранее выбранный снимок')
    for процесс in процессы:
        _сверить_вывод(папка / процесс['метка'], процесс)
    return {'схема': 'fum.серия-профилей-внимания.1', 'номер_родителя': os.getpid(),
            'источники_до': исходники, 'источники_после': copy.deepcopy(исходники), 'процессы': процессы,
            'граница': 'Три завершённых процесса и RAW; сверки SHA/режимов в сотрудничающей среде. '
                       'Не доказывает непрерывную неизменность между сверками или смысловое ревью.'}



"""Парный профиль планирования и синтетического ядра; не смысловое ревью."""

import argparse
from collections import Counter
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import platform
import statistics
import tempfile
import time
import tracemalloc


каталог = Path(__file__).resolve().parents[1]
репозиторий = 'fum-lab/fum'
сейчас = '2030-01-01T00:00:00+00:00'


def _байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def _хэш(значение):
    return hashlib.sha256(_байты(значение)).hexdigest()


def _модуль(имя, путь):
    спецификация = importlib.util.spec_from_file_location(имя, путь)
    результат = importlib.util.module_from_spec(спецификация)
    спецификация.loader.exec_module(результат)
    return результат


def _объект(номер):
    return {'id': 10000 + номер, 'number': номер, 'title': f'Синтетическое обращение {номер}',
            'body': ('Проверить точный вход, сохранить намерение, версии и основания решения. ' * 256) + str(номер),
            'state': 'open', 'updated_at': '2029-01-01T00:00:00Z',
            'html_url': f'https://github.com/fum-lab/fum/issues/{номер}'}


def _ядро(объект, версия, контекст_sha256):
    слова = (объект['title'] + ' ' + объект['body']).casefold().split()
    пары = Counter(zip(слова, слова[1:]))
    return {'версия': версия, 'контекст_sha256': контекст_sha256,
            'исходный_объект_sha256': _хэш(объект), 'слова': sorted(Counter(слова).items()),
            'пары': sorted((list(ключ), число) for ключ, число in пары.items())}


def _архив(архиватор, корень, метка, объекты, время):
    архиватор.импортировать(корень, репозиторий, метка,
        [('issues', _байты(объекты)), ('comments', b'[]')], полнота=True)
    путь = корень / 'Issues' / репозиторий / 'наблюдения' / метка / 'наблюдение.json'
    наблюдение = json.loads(путь.read_bytes()); наблюдение['время'] = время
    путь.write_bytes(_байты(наблюдение))


def _проход(внимание, корень, база, контекст, объекты, кэш, полный):
    начало = time.monotonic_ns()
    состояние = внимание.сверить(корень, репозиторий, база, контекст, сейчас)
    план = внимание.план_разбора(состояние, полный=полный,
        основание='Явный полный повтор на синтетическом входе профиля' if полный else None)
    планирование = time.monotonic_ns() - начало
    номера = {единица['номер'] for единица in план['единицы']}
    начало_ядра = time.monotonic_ns(); результаты = {}; вызовы = 0; байты = 0
    for объект in объекты:
        номер = str(объект['number']); версия = состояние['обращения'][номер]['ключ_версии']
        ключ = (номер, версия, состояние['контекст_sha256'])
        if номер in номера:
            результаты[номер] = _ядро(объект, версия, состояние['контекст_sha256'])
            вызовы += 1; байты += len(_байты(объект))
        else:
            результаты[номер] = кэш[ключ]
    ядро = time.monotonic_ns() - начало_ядра
    return {'планирование_нс': планирование, 'ядро_нс': ядро,
            'обработано': len(номера), 'вызовы_ядра': вызовы, 'обработано_байтов': байты,
            'результат_sha256': _хэш(результаты), 'состояние_sha256': _хэш(состояние)}


def измерить(*, число_обращений=64, повторы=3):
    if type(число_обращений) is not int or not 1 <= число_обращений <= 512:
        raise ValueError('Число обращений должно быть от 1 до 512')
    if type(повторы) is not int or not 1 <= повторы <= 20:
        raise ValueError('Число повторов должно быть от 1 до 20')
    внимание = _модуль('внимание_профиля', каталог / 'scripts/внимание_к_обсуждениям_GitHub.py')
    архиватор = _модуль('архив_профиля', каталог / 'scripts/архив_обсуждений_GitHub.py')
    контекст = {'цель': 'Синтетическое сравнение', 'полномочия': 'Только открытая фикстура',
               'критерий': 'Равенство статического результата всех обращений'}
    объекты = [_объект(номер) for номер in range(1, число_обращений + 1)]
    сценарии = []
    with tempfile.TemporaryDirectory() as временный:
        корень = Path(временный).resolve()
        _архив(архиватор, корень, 'первое', объекты, '2029-01-01T00:00:00+00:00')
        база = внимание.сверить(корень, репозиторий, внимание.начальное_состояние(репозиторий), контекст, сейчас)
        кэш = {}
        for объект in объекты:
            номер = str(объект['number']); версия = база['обращения'][номер]['ключ_версии']
            кэш[(номер, версия, база['контекст_sha256'])] = _ядро(объект, версия, база['контекст_sha256'])
            база = внимание.записать_ревью(база, номер, версия, база['контекст_sha256'],
                'рекомендовано', ['Явное синтетическое решение фикстуры; не ревью реального Issue'], сейчас)
        for индекс, имя in enumerate(['неизменный_вход', 'одна_редакция', 'другой_контекст']):
            текущие = copy.deepcopy(объекты); выбранный = copy.deepcopy(контекст)
            if индекс == 1:
                текущие[0]['body'] += '\nНовая синтетическая редакция при прежнем updated_at.'
                _архив(архиватор, корень, 'второе', текущие, '2029-01-02T00:00:00+00:00')
            elif индекс == 2:
                # Текущий архив тот же, что в сценарии редакции.
                текущие[0]['body'] += '\nНовая синтетическая редакция при прежнем updated_at.'
                выбранный['цель'] = 'Другая цель; старый кэш неприменим'
            вход = {'объекты': текущие, 'контекст': выбранный, 'база': база,
                    'наблюдения': [(путь.name, hashlib.sha256(путь.read_bytes()).hexdigest())
                        for путь in sorted((корень / 'Issues' / репозиторий / 'наблюдения').glob('*/наблюдение.json'))]}
            измерения = {'полный': [], 'дельта': []}
            порядок = []
            for повтор in range(повторы):
                варианты = ['полный', 'дельта'] if повтор % 2 == 0 else ['дельта', 'полный']
                порядок.append(варианты)
                for вариант in варианты:
                    измерения[вариант].append(_проход(внимание, корень, база, выбранный,
                        текущие, кэш, вариант == 'полный'))
            сводка = {}
            for вариант, прогоны in измерения.items():
                tracemalloc.start()
                try:
                    память = _проход(внимание, корень, база, выбранный, текущие, кэш, вариант == 'полный')
                    _, пик = tracemalloc.get_traced_memory()
                finally:
                    tracemalloc.stop()
                if any(часть['результат_sha256'] != память['результат_sha256'] for часть in прогоны):
                    raise AssertionError('Результат изменился между повторами')
                сводка[вариант] = {**{ключ: память[ключ] for ключ in ['обработано', 'вызовы_ядра',
                    'обработано_байтов', 'результат_sha256', 'состояние_sha256']},
                    'медиана_планирования_нс': statistics.median(часть['планирование_нс'] for часть in прогоны),
                    'медиана_ядра_нс': statistics.median(часть['ядро_нс'] for часть in прогоны),
                    'пик_дополнительных_выделений_байт': пик, 'измерения': прогоны}
            равны = (сводка['полный']['результат_sha256'] == сводка['дельта']['результат_sha256']
                     and сводка['полный']['состояние_sha256'] == сводка['дельта']['состояние_sha256'])
            ожидаемые = [0, 1, число_обращений][индекс]
            if not равны or сводка['дельта']['вызовы_ядра'] != ожидаемые or сводка['полный']['вызовы_ядра'] != число_обращений:
                raise AssertionError('Полный проход и дельта не подтвердили ожидаемый контракт')
            сценарии.append({'имя': имя, 'вход_sha256': _хэш(вход), 'контекст_sha256': _хэш(выбранный),
                              'равенство_результатов': равны, 'порядок_пар': порядок, **сводка})
    пути = [Path(__file__), каталог / 'scripts/внимание_к_обсуждениям_GitHub.py',
            каталог / 'scripts/архив_обсуждений_GitHub.py']
    return {'схема': 'fum.профиль-внимания-к-обсуждениям.1', 'число_обращений': число_обращений,
            'повторы': повторы, 'python': platform.python_version(), 'система': platform.system(),
            'машина': platform.machine(), 'код': {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in пути},
            'сценарии': сценарии,
            'граница': 'Планирование и синтетическое ядро обработки текста. Подготовка вне замера; кэш ОС не очищался. '
                'Пик отражает дополнительные выделения, уже созданный кэш не учтён. '
                'Смысловое ревью, модель, токены, сеть и полный рабочий цикл не измерены.'}


def выполнить():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--число-обращений', type=int, default=64)
    парсер.add_argument('--повторы', type=int, default=3)
    парсер.add_argument('--выход', type=Path, required=True)
    аргументы = парсер.parse_args()
    результат = измерить(число_обращений=аргументы.число_обращений, повторы=аргументы.повторы)
    with аргументы.выход.open('xb') as файл:
        файл.write(_байты(результат))
    print(json.dumps({'схема': результат['схема'], 'сценариев': len(результат['сценарии']),
                      'равенство': all(часть['равенство_результатов'] for часть in результат['сценарии'])}, ensure_ascii=False))


if __name__ == '__main__':
    выполнить()

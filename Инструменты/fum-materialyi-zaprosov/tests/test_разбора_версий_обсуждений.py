                исходные_покрытия = снимок_файлов(self.покрытия)
                запись = json.loads(next(self.покрытия.glob('*.json')).read_bytes())
                if режим == 'до-CAS':
                    self.assertTrue(self.план()['несогласованные'])
                р = self.работник('повтор', в); self.assertEqual(р.returncode, 0, р.stderr)
                self.assertFalse(self.план()['несогласованные'])
                ревью = внимание.загрузить(self.состояние, репозиторий)['обращения']['7']['ревью']
                self.assertEqual(ревью, [запись['ревью']])
                self.assertEqual((ревью[0]['время'], ревью[0]['решение'], ревью[0]['основания']),
                    (в['время'], в['суммарное']['решение'], в['суммарное']['основания']))
                self.assertEqual(снимок_файлов(self.покрытия), исходные_покрытия)
                if режим == 'до-CAS':
                    self.корень = self.база / 'архив-после'; self.корень.mkdir()
                    self.состояние = self.база / 'внимание-после'
                    self.покрытия = self.база / 'покрытия-после'
                    сохранить_архив(self.корень, 'первое', [комментарий()])


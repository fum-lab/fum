def обращение(текст='Тело'):
    return {'id': 70, 'number': 7, 'title': 'Обзор', 'body': текст, 'state': 'open',
            'updated_at': '2026-10-04T10:00:00Z',
            'html_url': 'https://github.com/fum-lab/fum/issues/7'}


def комментарий(номер=90, текст='Замечание'):
    return {'id': номер, 'body': текст, 'updated_at': '2026-10-04T10:00:00Z',
            'issue_url': 'https://api.github.com/repos/fum-lab/fum/issues/7',
            'html_url': f'https://github.com/fum-lab/fum/issues/7#issuecomment-{номер}'}


def сохранить_архив(корень, метка, комментарии, *, тело='Тело', полнота=True):
    архив.импортировать(корень, репозиторий, метка,
        [('issues', json.dumps([обращение(тело)], ensure_ascii=False).encode()),
         ('comments', json.dumps(комментарии, ensure_ascii=False).encode())], полнота=полнота)


def снимок_файлов(корень):
    return {str(п.relative_to(корень)): (hashlib.sha256(п.read_bytes()).hexdigest(),
            п.stat().st_mode, п.stat().st_ino, п.stat().st_mtime_ns)
            for п in корень.rglob('*') if п.is_file()}


def вход_оператора(план, *, ключи=None, суммарное=True):
    выбранные = план['единицы'] if ключи is None else [е for е in план['единицы'] if е['ключ'] in ключи]
    return {'схема': 'fum.решение-разбора-обсуждения.1', 'номер': '7',
            'план_sha256': план['выбор_sha256'], 'контекст': copy.deepcopy(контекст),
            'основания_разбора': copy.deepcopy(основания), 'время': сейчас,
            'происхождение': {'оператор': 'Оператор открытой фикстуры', 'источник': 'Адресный тест'},
            'решения': [{'ключ': е['ключ'], 'решение': 'рекомендовано',
                        'основания': ['Рассмотрена точная версия'],
                        'свидетельства': ['Открытое свидетельство']} for е in выбранные],
            'суммарное': {'решение': 'рекомендовано', 'основания': ['Явная суммарная оценка оператора'],
                         'полный_повтор_основание': None} if суммарное else None}



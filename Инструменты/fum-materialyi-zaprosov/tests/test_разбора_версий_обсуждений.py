    def test_метаданные_источника_и_родитель_подтверждаются_архивом(self):
        self.полный_разбор()
        def изменить(р, поле):
            for е in р['состав']:
                if поле == 'тип': е['объект']['тип'] = 'Неизвестный'
                elif поле == 'родитель': е['объект']['родитель']['id'] += 1
                else: е['объект']['наблюдение'][поле] = 100 if поле == 'порядок' else сейчас
                старый = е['ключ']
                е['ключ'] = self.разбор._ключ(е['объект'], е['контекст_sha256'], е['основания_sha256'])
                for в in р['вход']['решения']:
                    if в['ключ'] == старый: в['ключ'] = е['ключ']
                for з in р['решения']:
                    if з['единица']['ключ'] == старый: з['единица'] = copy.deepcopy(е)
            р['покрытие'] = {з['единица']['ключ']: внимание._хэш(з) for з in р['решения']}

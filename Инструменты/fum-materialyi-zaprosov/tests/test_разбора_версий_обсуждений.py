def исполнить_работника():
    режим, корень, состояние, покрытия, файл = sys.argv[2:]
    вход = json.loads(Path(файл).read_bytes())
    if режим != 'без-эффектов':
        модуль = загрузить('разбор_работника', каталог / 'scripts/разбор_версий_обсуждений.py')
    if режим == 'состязание':
        установить = модуль._установить
        def барьер(*а):
            print('READY', flush=True); sys.stdin.readline()
            return установить(*а)
        модуль._установить = барьер
        try:
            модуль.решение(Path(корень), репозиторий, Path(состояние), Path(покрытия), вход)
        except ValueError:
            raise SystemExit(2)
        return
    if режим in {'до-CAS', 'после-CAS'}:
        сохранить = модуль.внимание.сохранить
        def авария(*аргументы, **параметры):
            if режим == 'после-CAS': сохранить(*аргументы, **параметры)
            os._exit(73 if режим == 'до-CAS' else 74)
        модуль.внимание.сохранить = авария
        модуль.решение(Path(корень), репозиторий, Path(состояние), Path(покрытия), вход)
        raise AssertionError('Аварийная граница не достигнута')
    if режим == 'повтор':
        модуль.решение(Path(корень), репозиторий, Path(состояние), Path(покрытия), вход)
        return
    счётчики = {'API': 0, 'записи': 0}; открыть = os.open; текстовый = builtins.open; поточный = io.open
    def запрещённый_API(*аргументы, **параметры):
        счётчики['API'] += 1; raise AssertionError('API запрещён')
    def открыть_файл(путь, флаги, *аргументы, **параметры):
        if флаги & (os.O_CREAT | os.O_WRONLY | os.O_RDWR | os.O_TRUNC | os.O_APPEND):
            счётчики['записи'] += 1; raise AssertionError('Запись запрещена')
        return открыть(путь, флаги, *аргументы, **параметры)
    def открыть_текст(путь, режим='r', *аргументы, **параметры):
        if any(знак in режим for знак in 'wax+'):
            счётчики['записи'] += 1; raise AssertionError('Запись запрещена')
        return текстовый(путь, режим, *аргументы, **параметры)
    def открыть_поток(путь, режим='r', *аргументы, **параметры):
        if any(знак in режим for знак in 'wax+'):
            счётчики['записи'] += 1; raise AssertionError('Запись запрещена')
        return поточный(путь, режим, *аргументы, **параметры)
    def мутация(*аргументы, **параметры):
        счётчики['записи'] += 1; raise AssertionError('Мутация запрещена')
    до = снимок_файлов(Path(корень).parent)
    with patch.object(socket, 'socket', запрещённый_API), patch.object(subprocess, 'Popen', запрещённый_API), \
         patch.object(os, 'open', открыть_файл), patch.object(builtins, 'open', открыть_текст), \
         patch.object(io, 'open', открыть_поток), patch.object(os, 'mkdir', мутация), \
         patch.object(os, 'unlink', мутация), patch.object(os, 'rename', мутация), patch.object(os, 'replace', мутация):
        модуль = загрузить('разбор_работника', каталог / 'scripts/разбор_версий_обсуждений.py')
        модуль.решение(Path(корень), репозиторий, Path(состояние), Path(покрытия), вход)
        модуль.план(Path(корень), репозиторий, Path(состояние), Path(покрытия), '7', контекст, основания, сейчас)
        модуль.прочитать(Path(корень), репозиторий, Path(состояние), Path(покрытия), '7', контекст, основания, сейчас)
    assert до == снимок_файлов(Path(корень).parent)
    print(json.dumps(счётчики, ensure_ascii=False))


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == '--работник': исполнить_работника()
    else: unittest.main()

        чужое = внимание.загрузить(self.состояние, репозиторий)['обращения']['7']['ревью'][-1]
        self.assertEqual((чужое['решение'], чужое['основания']), ('отложено', ['Конкурент']))
        self.assertTrue(self.план()['несогласованные'])
        до = снимок_файлов(self.база)
        with self.assertRaises(ValueError): self.решить(в)
        self.assertEqual(до, снимок_файлов(self.база))


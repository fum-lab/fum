def загрузить(имя, путь):
    описание = importlib.util.spec_from_file_location(имя, путь)
    результат = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(результат)
    return результат


архив = загрузить('архив_покрытия_фикстуры', каталог / 'scripts/архив_обсуждений_GitHub.py')
внимание = загрузить('внимание_покрытия_фикстуры', каталог / 'scripts/внимание_к_обсуждениям_GitHub.py')

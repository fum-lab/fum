    def test_конкурентный_снимок_не_теряет_уже_сохранённое_ревью(self):
        self.сохранить_архив('первое'); self.сверить()
        папка = self.корень / 'частное'
        внимание.сохранить(папка, self.состояние, ожидаемый_sha256=None)
        файл = папка / 'состояние.json'; исходные = файл.read_bytes()
        новое = внимание.записать_ревью(self.состояние, '7',
            self.состояние['обращения']['7']['ключ_версии'], self.состояние['контекст_sha256'],
            'рекомендовано', ['Независимое сохранённое ревью'], сейчас)
        прочитать = Path.read_bytes; переключено = False
        def переключить(путь):
            nonlocal переключено
            результат = прочитать(путь)
            if путь == файл and not переключено:
                переключено = True
                внимание.сохранить(папка, новое, ожидаемый_sha256=hashlib.sha256(исходные).hexdigest())
            return результат
        файл_контекста = self.корень / 'контекст.json'; файл_контекста.write_bytes(байты(контекст))
        аргументы = ['внимание', '--состояние', str(папка), '--корень-архива', str(self.корень),
                     '--контекст', str(файл_контекста), '--сейчас', сейчас, 'сверить']
        with patch.object(Path, 'read_bytes', переключить), patch.object(sys, 'argv', аргументы), contextlib.redirect_stdout(io.StringIO()):
            код = внимание.выполнить()
        self.assertTrue(переключено)
        self.assertEqual(код, 2)
        self.assertEqual(внимание.загрузить(папка, репозиторий), новое)


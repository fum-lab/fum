def _байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2,
                       allow_nan=False) + '\n').encode('utf-8')


def _хэш(значение):
    return hashlib.sha256(_байты(значение)).hexdigest()


def _пары(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ValueError('Повторный ключ JSON')
        результат[ключ] = значение
    return результат


def _декодировать(байты):
    def запретить(значение):
        raise ValueError('Нечисловая константа JSON')
    return json.loads(байты, object_pairs_hook=_пары, parse_constant=запретить)


def _время(значение):
    if not isinstance(значение, str):
        raise ValueError('Нет точного времени')
    результат = datetime.fromisoformat(значение.replace('Z', '+00:00'))
    if результат.tzinfo is None:
        raise ValueError('Время без часовой зоны')
    return результат


def _контекст(значение):
    if not isinstance(значение, dict) or not значение:
        raise ValueError('Нужен явно выбранный непустой контекст')
    return _хэш(значение)


def _путь(путь, *, вне_репозитория=False):
    путь = Path(путь)
    if not путь.is_absolute() or путь != путь.resolve():
        raise ValueError('Нужен физический абсолютный путь')
    for компонент in [путь, *путь.parents]:
        if компонент.is_symlink():
            raise ValueError('Символическая ссылка в пути')
        if вне_репозитория and (компонент / '.git').exists():
            raise ValueError('Состояние должно оставаться вне Git')
    return путь


def начальное_состояние(репозиторий):
    if not isinstance(репозиторий, str) or not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', репозиторий):
        raise ValueError('Нужен точный репозиторий')
    if any(часть in {'.', '..'} for часть in репозиторий.split('/')):
        raise ValueError('Неканонический репозиторий')
    return {'схема': 'fum.внимание-к-обсуждениям.1', 'репозиторий': репозиторий,
            'контекст': None, 'контекст_sha256': None, 'период_секунд': None,
            'сбор': {'состояние': 'неизвестно', 'полнота': False,
                     'последнее': None, 'последнее_полное': None},
            'наблюдения': {}, 'обращения': {}, 'версии_для_разбора': {}, 'сигналы': {},
            'снятие_исторического_внимания': []}


def _проверить_состояние(состояние, репозиторий):
    образец = начальное_состояние(репозиторий)
    if not isinstance(состояние, dict) or set(состояние) != set(образец):
        raise ValueError('Иной контракт состояния')
    if состояние['схема'] != образец['схема'] or состояние['репозиторий'] != репозиторий:
        raise ValueError('Иная схема или репозиторий')
    for ключ in ['наблюдения', 'обращения', 'версии_для_разбора', 'сигналы', 'сбор']:
        if not isinstance(состояние[ключ], dict):
            raise ValueError('Неверная структура состояния')
    if not isinstance(состояние['снятие_исторического_внимания'], list):
        raise ValueError('Нет истории решений')
    if type(состояние['сбор'].get('полнота')) is not bool:
        raise ValueError('Неизвестная полнота')
    if состояние['контекст'] is not None and _контекст(состояние['контекст']) != состояние['контекст_sha256']:
        raise ValueError('Подмена контекста')
    метки = set()
    for ключ, наблюдение in состояние['наблюдения'].items():
        if (set(наблюдение) != {'метка', 'порядок', 'время', 'sha256'}
                or type(наблюдение['порядок']) is not int or наблюдение['порядок'] <= 0
                or ключ != str(наблюдение['порядок'])
                or not isinstance(наблюдение['метка'], str) or наблюдение['метка'] in метки
                or not re.fullmatch(r'[0-9a-f]{64}', наблюдение['sha256'])):
            raise ValueError('Повреждённый перечень наблюдений')
        _время(наблюдение['время']); метки.add(наблюдение['метка'])
    подтверждённые = set(); идентификаторы = {}
    for номер, запись in состояние['обращения'].items():
        if not isinstance(номер, str) or not re.fullmatch(r'[1-9][0-9]*', номер):
            raise ValueError('Неканонический номер')
        идентичность = запись['идентичность']
        if (идентичность['репозиторий'] != репозиторий or идентичность['номер'] != номер
                or type(идентичность['id']) is not int or идентичность['id'] <= 0
                or идентичность['тип'] not in {'Issue', 'PR'}):
            raise ValueError('Неверная идентичность')
        if идентичность['id'] in идентификаторы and идентификаторы[идентичность['id']] != номер:
            raise ValueError('Коллизия постоянного идентификатора')
        идентификаторы[идентичность['id']] = номер
        вход = {'идентичность': идентичность, 'обращение': запись['текущее_обращение']['sha256'],
                'комментарии': {ключ: часть['sha256'] for ключ, часть in запись['текущие_комментарии'].items()}}
        if запись['вход'] != вход or запись['ключ_версии'] != _хэш(вход):
            raise ValueError('Подмена связанного входа')
        применимые = {}
        for ревью in запись['ревью']:
            тело = {ключ: часть for ключ, часть in ревью.items() if ключ != 'sha256'}
            if (ревью['схема'] != 'fum.ревью-наблюдённой-версии.1' or ревью['sha256'] != _хэш(тело)
                    or ревью['идентичность'] != идентичность or ревью['вход']['идентичность'] != идентичность
                    or ревью['версия'] != _хэш(ревью['вход'])
                    or ревью['контекст_sha256'] != _контекст(ревью['контекст'])):
                raise ValueError('Повреждённое или чужое ревью')
            _время(ревью['время'])
            применимые[ревью['sha256']] = ревью
            подтверждённые.add((номер, ревью['версия'], ревью['контекст_sha256']))
        ссылка = запись['применимое_ревью']
        if ссылка is not None:
            ревью = применимые.get(ссылка)
            if (ревью is None or ревью['версия'] != запись['ключ_версии']
                    or ревью['контекст_sha256'] != состояние['контекст_sha256']
                    or запись['разбор'] != {'состояние': 'разобрано', 'время': ревью['время']}):
                raise ValueError('Необоснованная применимость ревью')
        elif запись['разбор'] != {'состояние': 'не разобрано', 'время': None}:
            raise ValueError('Разбор без связанного ревью')
        for стадия in ['принятие', 'назначение', 'выполнение']:
            if запись[стадия] != {'состояние': 'не выполнялось', 'время': None}:
                raise ValueError('Эта версия слоя не принимает внешние стадии')
    for ключ, версия in состояние['версии_для_разбора'].items():
        if ключ != _хэш({'номер': версия['номер'], 'версия': версия['версия'],
                        'контекст_sha256': версия['контекст_sha256']}):
            raise ValueError('Подмена идентичности остатка')
        if type(версия['разобрано']) is not bool:
            raise ValueError('Неизвестный разбор')
        if версия['версия'] != _хэш(версия['вход']) or версия['вход']['идентичность'] != состояние['обращения'][версия['номер']]['идентичность']:
            raise ValueError('Подмена входа исторической версии')
        if версия['разобрано'] != ((версия['номер'], версия['версия'], версия['контекст_sha256']) in подтверждённые):
            raise ValueError('Флаг разбора не связан с проверенным ревью')
    for решение in состояние['снятие_исторического_внимания']:
        тело = {ключ: часть for ключ, часть in решение.items() if ключ != 'sha256'}
        версия = состояние['версии_для_разбора'].get(решение['ключ'])
        if (версия is None or решение['sha256'] != _хэш(тело) or решение['ревью_выполнено'] is not False
                or решение['замещающее_наблюдение']['порядок'] <= версия['наблюдение']['порядок']):
            raise ValueError('Повреждённое историческое решение')
    _байты(состояние)


def _архиватор():
    путь = Path(__file__).resolve().with_name('архив_обсуждений_GitHub.py')
    спецификация = importlib.util.spec_from_file_location('архив_внимания', путь)
    результат = importlib.util.module_from_spec(спецификация)
    спецификация.loader.exec_module(результат)
    return результат


def _снимок(корень, репозиторий):
    корень = _путь(корень)
    архиватор = _архиватор()
    история = архиватор.прочитать(корень, репозиторий)
    if not история['наблюдения']:
        raise ValueError('Нет наблюдений; это не пустая очередь')
    база = корень / 'Issues' / репозиторий
    обращения = {}; комментарии = {}; страницы = {}; кадры = []; последнее_полное = None; идентификаторы = {}
    for наблюдение in история['наблюдения']:
        if type(наблюдение.get('порядок')) is not int or наблюдение['порядок'] <= 0:
            raise ValueError('Неизвестный порядок')
        if type(наблюдение.get('полнота')) is not bool:
            raise ValueError('Неизвестная полнота')
        _время(наблюдение['время'])
        метка = наблюдение['метка']
        if not isinstance(метка, str) or not re.fullmatch(r'[\w.-]{1,160}', метка) or метка in {'.', '..'}:
            raise ValueError('Неизвестная метка')
        файл = база / 'наблюдения' / метка / 'наблюдение.json'
        исходные = файл.read_bytes()
        if _декодировать(исходные) != наблюдение:
            raise ValueError('Наблюдение изменилось при чтении')
        источник = {'метка': метка, 'порядок': наблюдение['порядок'],
                    'время': наблюдение['время'], 'sha256': hashlib.sha256(исходные).hexdigest()}
        виденные_обращения = set(); виденные_комментарии = set()
        виды = {страница['тип'] for страница in наблюдение['страницы']}
        if наблюдение['полнота'] and (наблюдение['состояние'] != 'завершено' or виды != {'issues', 'comments'}):
            raise ValueError('Полнота не содержит обе цепочки')
        for страница in наблюдение['страницы']:
            хэш = страница['sha256']; тип = страница['тип']; ключ = (тип, хэш)
            if ключ not in страницы:
                исходные = (база / 'данные' / (хэш + '.json')).read_bytes()
                if hashlib.sha256(исходные).hexdigest() != хэш or len(исходные) != страница['байты']:
                    raise ValueError('Страница изменилась при чтении')
                записи = архиватор._проверить_записи(тип, исходные, репозиторий)
                страницы[ключ] = [(запись, _хэш(запись),
                    {имя: _хэш(значение) for имя, значение in запись.items()}) for запись in записи]
            for запись, версия, поля in страницы[ключ]:
                _время(запись['updated_at'])
                номер = str(запись['number']) if тип == 'issues' else запись['issue_url'].rsplit('/', 1)[1]
                привязка = {'sha256': версия, 'страница_sha256': хэш,
                            'наблюдение': источник, 'updated_at': запись['updated_at'], 'поля': поля}
                if тип == 'issues':
                    идентичность = {'репозиторий': репозиторий, 'номер': номер,
                        'id': запись['id'], 'тип': 'PR' if 'pull_request' in запись else 'Issue'}
                    if номер in обращения and обращения[номер]['идентичность'] != идентичность:
                        raise ValueError('Коллизия идентичности обращения')
                    if запись['id'] in идентификаторы and идентификаторы[запись['id']] != номер:
                        raise ValueError('Один постоянный ID имеет разные номера')
                    идентификаторы[запись['id']] = номер
                    обращения[номер] = {'идентичность': идентичность, 'объект': привязка}
                    виденные_обращения.add(номер)
                else:
                    идентификатор = str(запись['id'])
                    if идентификатор in комментарии and комментарии[идентификатор]['номер'] != номер:
                        raise ValueError('Комментарий изменил родителя')
                    комментарии[идентификатор] = {'номер': номер, 'объект': привязка}
                    виденные_комментарии.add(идентификатор)
        if any(комментарий['номер'] not in обращения for комментарий in комментарии.values()):
            raise ValueError('Родитель комментария неизвестен')
        пропуски = []
        if наблюдение['полнота']:
            последнее_полное = источник
            пропуски = (['обращение:' + номер for номер in sorted(set(обращения) - виденные_обращения)]
                + ['комментарий:' + номер for номер in sorted(set(комментарии) - виденные_комментарии)])
        единицы = {}
        по_родителям = {}
        for идентификатор, комментарий in комментарии.items():
            по_родителям.setdefault(комментарий['номер'], {})[идентификатор] = комментарий['объект']
        for номер, обращение in обращения.items():
            текущие = по_родителям.get(номер, {})
            вход = {'идентичность': обращение['идентичность'],
                    'обращение': обращение['объект']['sha256'],
                    'комментарии': {ключ: значение['sha256'] for ключ, значение in текущие.items()}}
            единицы[номер] = {**обращение, 'комментарии': текущие, 'версия': _хэш(вход), 'вход': вход}
        кадры.append({'источник': источник, 'полнота': наблюдение['полнота'],
                      'единицы': единицы, 'пропуски': пропуски})
    return кадры, последнее_полное


def _сигнал(состояние, причина, привязка):
    данные = {'причина': причина, 'привязка': привязка}
    ключ = _хэш(данные)
    состояние['сигналы'][ключ] = {**данные, 'активен': True}


def _дельта(единица, прежнее, контекст_sha256):
    if прежнее is None:
        return {'поля_обращения': sorted(единица['объект']['поля']),
                'новые_комментарии': sorted(единица['комментарии']),
                'изменённые_комментарии': [], 'контекст_изменён': False}
    поля = единица['объект']['поля']; старые = прежнее['поля_обращения']
    комментарии = единица['вход']['комментарии']; прежние = прежнее['вход']['комментарии']
    return {'поля_обращения': sorted(ключ for ключ in set(поля) | set(старые) if поля.get(ключ) != старые.get(ключ)),
            'новые_комментарии': sorted(set(комментарии) - set(прежние)),
            'изменённые_комментарии': sorted(ключ for ключ in set(комментарии) & set(прежние)
                                            if комментарии[ключ] != прежние[ключ]),
            'контекст_изменён': прежнее['контекст_sha256'] != контекст_sha256}


def сверить(корень, репозиторий, состояние, контекст, сейчас, *, период_секунд=None):
    _проверить_состояние(состояние, репозиторий)
    хэш_контекста = _контекст(контекст); время = _время(сейчас)
    if период_секунд is not None and (type(период_секунд) is not int or период_секунд <= 0):
        raise ValueError('Период задаётся явно положительными целыми секундами')
    результат = copy.deepcopy(состояние)
    результат.update({'контекст': copy.deepcopy(контекст), 'контекст_sha256': хэш_контекста,
                      'период_секунд': период_секунд})
    try:
        кадры, последнее_полное = _снимок(корень, репозиторий)
        if any(_время(кадр['источник']['время']) > время for кадр in кадры):
            raise ValueError('Наблюдение из будущего относительно выбранного времени')
        источники = {кадр['источник']['порядок']: кадр['источник'] for кадр in кадры}
        сохранённые = состояние['наблюдения'].values()
        if any(источники.get(источник['порядок']) != источник for источник in сохранённые):
            raise ValueError('Архив потерял или изменил подтверждённое наблюдение')
    except (OSError, ValueError, TypeError, KeyError) as ошибка:
        if хэш_контекста != состояние['контекст_sha256']:
            for номер, запись in результат['обращения'].items():
                запись['применимое_ревью'] = None
                запись['разбор'] = {'состояние': 'не разобрано', 'время': None}
                запись['дельта']['контекст_изменён'] = True
                ключ = _хэш({'номер': номер, 'версия': запись['ключ_версии'], 'контекст_sha256': хэш_контекста})
                результат['версии_для_разбора'].setdefault(ключ, {
                    'номер': номер, 'версия': запись['ключ_версии'], 'контекст_sha256': хэш_контекста,
                    'вход': запись['вход'], 'наблюдение': состояние['сбор']['последнее'], 'разобрано': False})
        результат['сбор'].update({'состояние': 'неизвестно', 'полнота': False})
        _сигнал(результат, 'неизвестность_архива', {'класс': type(ошибка).__name__})
        _сигналы_остатка(результат)
        return результат
    результат['наблюдения'] = {str(ключ): copy.deepcopy(источник) for ключ, источник in источники.items()}
    for сигнал in результат['сигналы'].values():
        сигнал['активен'] = False
    for кадр in кадры:
        for номер, единица in кадр['единицы'].items():
            ключ = _хэш({'номер': номер, 'версия': единица['версия'], 'контекст_sha256': хэш_контекста})
            результат['версии_для_разбора'].setdefault(ключ, {
                'номер': номер, 'версия': единица['версия'], 'контекст_sha256': хэш_контекста,
                'вход': единица['вход'], 'наблюдение': кадр['источник'], 'разобрано': False})
    последний = кадры[-1]
    for номер, единица in последний['единицы'].items():
        прежняя = результат['обращения'].get(номер)
        ревью = прежняя['ревью'] if прежняя else []
        применимые = [запись for запись in ревью if запись['версия'] == единица['версия']
                      and запись['контекст_sha256'] == хэш_контекста]
        применимое = применимые[-1] if применимые else None
        результат['обращения'][номер] = {
            'идентичность': единица['идентичность'], 'ключ_версии': единица['версия'],
            'текущее_обращение': единица['объект'], 'текущие_комментарии': единица['комментарии'],
            'вход': единица['вход'], 'ревью': ревью,
            'применимое_ревью': применимое['sha256'] if применимое else None,
            'разбор': {'состояние': 'разобрано' if применимое else 'не разобрано',
                       'время': применимое['время'] if применимое else None},
            'принятие': {'состояние': 'не выполнялось', 'время': None},
            'назначение': {'состояние': 'не выполнялось', 'время': None},
            'выполнение': {'состояние': 'не выполнялось', 'время': None},
            'дельта': _дельта(единица, применимое or (ревью[-1] if ревью else None), хэш_контекста)}
    результат['сбор'] = {'состояние': 'наблюдено', 'полнота': последний['полнота'],
                         'последнее': последний['источник'], 'последнее_полное': последнее_полное}
    if not последний['полнота']:
        _сигнал(результат, 'неполный_обход', последний['источник'])
    пропуски = next((кадр['пропуски'] for кадр in reversed(кадры) if кадр['полнота']), [])
    if пропуски:
        _сигнал(результат, 'отсутствие_не_доказывает_удаление', {'объекты': пропуски, 'наблюдение': последнее_полное})
    if период_секунд is not None and (последнее_полное is None
            or (время - _время(последнее_полное['время'])).total_seconds() > период_секунд):
        _сигнал(результат, 'просрочено_наблюдение', {'последнее_полное': последнее_полное, 'период_секунд': период_секунд})
    _сигналы_остатка(результат)
    return результат


def _сигналы_остатка(состояние):
    снятые = {решение['ключ'] for решение in состояние['снятие_исторического_внимания']}
    for ключ, версия in состояние['версии_для_разбора'].items():
        текущая = состояние['обращения'].get(версия['номер'])
        актуальна = (текущая is not None and текущая['ключ_версии'] == версия['версия']
                    and состояние['контекст_sha256'] == версия['контекст_sha256'])
        данные = {'ключ': ключ, 'номер': версия['номер'], 'версия': версия['версия'],
                  'контекст_sha256': версия['контекст_sha256']}
        сигнал = _хэш({'причина': 'версия_без_разбора', 'привязка': данные})
        if not версия['разобрано'] and (актуальна or ключ not in снятые):
            _сигнал(состояние, 'версия_без_разбора', данные)
        elif сигнал in состояние['сигналы']:
            состояние['сигналы'][сигнал]['активен'] = False


def записать_ревью(состояние, номер, версия, контекст_sha256, решение, основания, время,
                  *, полный_повтор_основание=None):
    _проверить_состояние(состояние, состояние['репозиторий']); _время(время)
    if состояние['сбор']['состояние'] != 'наблюдено':
        raise ValueError('Неизвестное наблюдение не допускает ревью')
    запись = состояние['обращения'].get(str(номер))
    if запись is None or версия != запись['ключ_версии'] or контекст_sha256 != состояние['контекст_sha256']:
        raise ValueError('Ревью не соответствует текущим версии и контексту')
    if решение not in {'рекомендовано', 'отложено', 'отклонено'} or not isinstance(основания, list) or not основания or any(not isinstance(часть, str) or not часть.strip() for часть in основания):
        raise ValueError('Нужны явные решение и основания')
    if запись['применимое_ревью'] is not None and (not isinstance(полный_повтор_основание, str) or not полный_повтор_основание.strip()):
        raise ValueError('Повтор применимого ревью требует отдельного основания')
    результат = copy.deepcopy(состояние); запись = результат['обращения'][str(номер)]
    ревью = {'схема': 'fum.ревью-наблюдённой-версии.1', 'версия': версия,
             'идентичность': запись['идентичность'], 'контекст_sha256': контекст_sha256,
             'контекст': результат['контекст'], 'вход': запись['вход'],
             'поля_обращения': запись['текущее_обращение']['поля'],
             'решение': решение, 'основания': copy.deepcopy(основания), 'время': время,
             'полный_повтор_основание': полный_повтор_основание,
             'граница': 'Запись решения оператора; не доказательство адекватности, принятия или выполнения.'}
    ревью['sha256'] = _хэш(ревью); запись['ревью'].append(ревью)
    запись['применимое_ревью'] = ревью['sha256']; запись['разбор'] = {'состояние': 'разобрано', 'время': время}
    запись['дельта'] = {'поля_обращения': [], 'новые_комментарии': [],
                       'изменённые_комментарии': [], 'контекст_изменён': False}
    ключ = _хэш({'номер': str(номер), 'версия': версия, 'контекст_sha256': контекст_sha256})
    результат['версии_для_разбора'][ключ]['разобрано'] = True
    _сигналы_остатка(результат)
    return результат


def снять_историческое_внимание(состояние, ключ, замещающая_версия, автор, основание, время):
    _проверить_состояние(состояние, состояние['репозиторий']); _время(время)
    вход = {'ключ': ключ, 'замещающая_версия': замещающая_версия,
            'автор': автор, 'основание': основание, 'время': время}
    прежние = [часть for часть in состояние['снятие_исторического_внимания'] if часть['ключ'] == ключ]
    if прежние:
        if len(прежние) != 1 or {поле: прежние[0][поле] for поле in вход} != вход:
            raise ValueError('Прежнее решение нельзя переписать')
        return copy.deepcopy(состояние)
    версия = состояние['версии_для_разбора'].get(ключ)
    if версия is None or состояние['сбор']['состояние'] != 'наблюдено' or not состояние['сбор']['полнота']:
        raise ValueError('Нужны известная версия и полный наблюдённый вход')
    текущая = состояние['обращения'][версия['номер']]
    if текущая['ключ_версии'] == версия['версия'] or замещающая_версия != текущая['ключ_версии']:
        raise ValueError('Нужна точная поздняя замещающая версия')
    if состояние['сбор']['последнее']['порядок'] <= версия['наблюдение']['порядок']:
        raise ValueError('Замещение не является поздним наблюдением')
    if any(not isinstance(часть, str) or not часть.strip() for часть in [автор, основание]):
        raise ValueError('Нужны автор и содержательное основание')
    решение = {**вход,
               'замещающее_наблюдение': copy.deepcopy(состояние['сбор']['последнее']),
               'состояние': 'снято с исторического внимания', 'ревью_выполнено': False}
    решение['sha256'] = _хэш(решение)
    результат = copy.deepcopy(состояние); результат['снятие_исторического_внимания'].append(решение)
    _сигналы_остатка(результат)
    return результат


def остаток(состояние):
    _проверить_состояние(состояние, состояние['репозиторий'])
    снятые = {часть['ключ'] for часть in состояние['снятие_исторического_внимания']}
    версии = []
    for ключ, версия in состояние['версии_для_разбора'].items():
        актуальна = (состояние['обращения'].get(версия['номер'], {}).get('ключ_версии') == версия['версия']
                    and состояние['контекст_sha256'] == версия['контекст_sha256'])
        if not версия['разобрано'] and (актуальна or ключ not in снятые):
            версии.append({'ключ': ключ, **версия, 'текущая': актуальна})
    return {'номера': sorted(номер for номер, запись in состояние['обращения'].items()
                            if запись['применимое_ревью'] is None),
            'версии': sorted(версии, key=lambda часть: часть['ключ']),
            'сигналы': sorted(ключ for ключ, запись in состояние['сигналы'].items() if запись['активен']),
            'сбор': copy.deepcopy(состояние['сбор'])}


def план_разбора(состояние, *, полный=False, основание=None):
    if полный and (not isinstance(основание, str) or not основание.strip()):
        raise ValueError('Полный повтор требует сохранённого основания')
    _проверить_состояние(состояние, состояние['репозиторий'])
    единицы = []
    for номер, запись in sorted(состояние['обращения'].items()):
        if полный or запись['применимое_ревью'] is None:
            единицы.append({'номер': номер, 'версия': запись['ключ_версии'],
                'контекст_sha256': состояние['контекст_sha256'],
                'режим': 'полный' if полный or not запись['ревью'] or запись['дельта']['контекст_изменён'] else 'дельта',
                'дельта': copy.deepcopy(запись['дельта'])})
    return {'единицы': единицы, 'исторический_остаток': [часть for часть in остаток(состояние)['версии'] if not часть['текущая']],
            'полный_повтор_основание': основание if полный else None,
            'граница': 'План проверки входа; смысловой разбор и вызов модели не выполняются.'}


def _загрузить_с_хэшем(каталог, репозиторий):
    каталог = _путь(каталог, вне_репозитория=True); файл = каталог / 'состояние.json'
    if not файл.exists():
        if каталог.exists() and any(часть.name != '.lock' for часть in каталог.iterdir()):
            raise ValueError('Неизвестный остаток установки состояния')
        return начальное_состояние(репозиторий), None
    if файл.is_symlink() or not файл.is_file() or файл.stat().st_nlink != 1:
        raise ValueError('Нужен обычный собственный файл состояния')
    байты = файл.read_bytes()
    обёртка = _декодировать(байты)
    if not isinstance(обёртка, dict) or set(обёртка) != {'схема', 'sha256', 'состояние'} or обёртка['схема'] != 'fum.сохранение-внимания.1':
        raise ValueError('Повреждённая обёртка состояния')
    if _хэш(обёртка['состояние']) != обёртка['sha256']:
        raise ValueError('Повреждённое состояние')
    _проверить_состояние(обёртка['состояние'], репозиторий)
    return обёртка['состояние'], hashlib.sha256(байты).hexdigest()


def загрузить(каталог, репозиторий):
    return _загрузить_с_хэшем(каталог, репозиторий)[0]


def _синхронизировать(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def сохранить(каталог, состояние, *, ожидаемый_sha256):
    _проверить_состояние(состояние, состояние['репозиторий']); каталог = _путь(каталог, вне_репозитория=True)
    if not каталог.exists():
        каталог.mkdir(mode=0o700); _синхронизировать(каталог.parent)
    if not каталог.is_dir() or каталог.stat().st_uid != os.getuid():
        raise ValueError('Нужен собственный каталог состояния')
    замок = os.open(каталог / '.lock', os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    временный = None
    try:
        fcntl.flock(замок, fcntl.LOCK_EX)
        файл = каталог / 'состояние.json'; есть = файл.exists()
        if есть:
            загрузить(каталог, состояние['репозиторий'])
            исходные = файл.read_bytes()
            if hashlib.sha256(исходные).hexdigest() != ожидаемый_sha256:
                raise ValueError('Состояние изменилось после чтения')
        elif ожидаемый_sha256 is not None:
            raise ValueError('Исчезло выбранное состояние')
        else:
            загрузить(каталог, состояние['репозиторий'])
        байты = _байты({'схема': 'fum.сохранение-внимания.1', 'sha256': _хэш(состояние), 'состояние': состояние})
        if есть and исходные == байты:
            return False
        дескриптор, имя = tempfile.mkstemp(prefix='.установка-', dir=каталог)
        временный = Path(имя)
        with os.fdopen(дескриптор, 'wb') as выход:
            выход.write(байты); выход.flush(); os.fsync(выход.fileno())
        os.replace(временный, файл); временный = None; _синхронизировать(каталог)
        return True
    finally:
        if временный is not None:
            временный.unlink(missing_ok=True)
        os.close(замок)



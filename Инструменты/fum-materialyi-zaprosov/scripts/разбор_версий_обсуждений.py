"""Пообъектное покрытие поверх прежних архива и агрегатного внимания.

Решение задаёт оператор. Канонический SHA объекта не является SHA сырых
байтов страницы. Чтение и точный завершённый повтор не создают файлов.
"""
import argparse
import copy
import fcntl
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import stat
import tempfile


описание = importlib.util.spec_from_file_location('внимание_покрытия',
    Path(__file__).resolve().with_name('внимание_к_обсуждениям_GitHub.py'))
внимание = importlib.util.module_from_spec(описание)
описание.loader.exec_module(внимание)
байты = внимание._байты
хэш = внимание._хэш


def требовать(условие, причина):
    if not условие:
        raise ValueError(причина)


def _поля(значение, имена):
    требовать(type(значение) is dict and set(значение) == set(имена), 'Неизвестные поля контракта')


def _строки(значение):
    требовать(type(значение) is list and значение
        and all(type(ч) is str and ч.strip() for ч in значение), 'Нужны непустые основания и свидетельства')


def _каталоги(каталог_внимания, каталог_покрытий):
    а = внимание._путь(каталог_внимания, вне_репозитория=True)
    п = внимание._путь(каталог_покрытий, вне_репозитория=True)
    требовать(not (а.is_relative_to(п) or п.is_relative_to(а)), 'Каталоги внимания и покрытия должны быть раздельными')
    for к in (а, п):
        if к.exists():
            с = к.stat()
            требовать(к.is_dir() and с.st_uid == os.getuid(), 'Нужен собственный каталог')
    return а, п


def _прочитать_файл(путь):
    внимание._путь(путь)
    def устойчивые(с):
        return (с.st_dev, с.st_ino, с.st_mode, с.st_nlink, с.st_uid, с.st_gid,
            с.st_size, с.st_mtime_ns, с.st_ctime_ns)
    до = путь.lstat()
    требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1 and до.st_uid == os.getuid(),
        'Нужен собственный обычный файл без ссылок')
    д = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(д, 'rb') as поток:
        требовать(устойчивые(до) == устойчивые(os.fstat(д)), 'Файл подменён до чтения')
        сырые = поток.read()
        требовать(устойчивые(до) == устойчивые(os.fstat(д)), 'Файл изменился при чтении')
    требовать(устойчивые(до) == устойчивые(путь.lstat()), 'Файл заменён после чтения')
    return сырые


def _основания(выбор, метка):
    _поля(выбор, {'общие', 'объекты'})
    требовать(type(выбор['общие']) is dict and выбор['общие']
        and type(выбор['объекты']) is dict, 'Нужны явно выбранные основания разбора')
    частные = выбор['объекты'].get(метка, {})
    требовать(type(частные) is dict, 'Неверные адресные основания')
    return {'общие': выбор['общие'], 'объект': частные}


def _метка(объект):
    return объект['тип'] + ':' + объект['id']


def _ключ(объект, контекст_sha256, основания_sha256):
    return хэш({'репозиторий': объект['репозиторий'], 'родитель': объект['родитель'],
        'тип': объект['тип'], 'id': объект['id'], 'версия_sha256': объект['версия_sha256'],
        'контекст_sha256': контекст_sha256, 'основания_sha256': основания_sha256})


def _sha(значение):
    return type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение)


def _проверить_единицу(е, р):
    _поля(е, {'ключ', 'объект', 'контекст_sha256', 'основания_sha256'})
    о = е['объект']
    _поля(о, {'репозиторий', 'родитель', 'тип', 'id', 'версия_sha256', 'страница_sha256', 'наблюдение'})
    родитель = о['родитель']; н = о['наблюдение']
    _поля(родитель, {'репозиторий', 'номер', 'id', 'тип'})
    _поля(н, {'метка', 'порядок', 'время', 'sha256'})
    требовать(родитель['репозиторий'] == р['репозиторий'] and родитель['номер'] == р['вход']['номер']
        and type(родитель['id']) is int and родитель['id'] > 0 and родитель['тип'] in {'Issue', 'PR'}
        and о['репозиторий'] == р['репозиторий'] and о['тип'] in {'Issue', 'PR', 'комментарий'}
        and type(о['id']) is str and re.fullmatch('[1-9][0-9]*', о['id'])
        and (о['тип'] == 'комментарий' or (о['тип'] == родитель['тип'] and о['id'] == str(родитель['id'])))
        and _sha(о['версия_sha256']) and _sha(о['страница_sha256']) and _sha(н['sha256'])
        and type(н['метка']) is str and re.fullmatch(r'[\w.-]{1,160}', н['метка']) and н['метка'] not in {'.', '..'}
        and type(н['порядок']) is int and н['порядок'] > 0, 'Неверная идентичность или источник единицы')
    внимание._время(н['время'])
    требовать(е['контекст_sha256'] == внимание._контекст(р['вход']['контекст'])
        and е['основания_sha256'] == хэш(_основания(р['вход']['основания_разбора'], _метка(о)))
        and е['ключ'] == _ключ(о, е['контекст_sha256'], е['основания_sha256']), 'Подмена пообъектной применимости')


def _вход_состава(состав):
    объекты = [е['объект'] for е in состав]
    родители = [о for о in объекты if о['тип'] in {'Issue', 'PR'}]
    требовать(len(родители) == 1 and all(о['родитель'] == родители[0]['родитель'] for о in объекты),
        'Неоднозначный родитель агрегатного входа')
    требовать(len({(о['тип'], о['id']) for о in объекты}) == len(объекты),
        'Две версии одной идентичности в выбранном составе')
    родитель = родители[0]
    return {'идентичность': родитель['родитель'], 'обращение': родитель['версия_sha256'],
        'комментарии': {о['id']: о['версия_sha256'] for о in объекты if о['тип'] == 'комментарий'}}


def _проверить_ревью(р):
    в = р['ревью']; с = р['вход']['суммарное']; вход = _вход_состава(р['состав'])
    выбор = {'репозиторий': р['репозиторий'], 'номер': р['вход']['номер'], 'состав': р['состав'],
        'контекст_sha256': внимание._контекст(р['вход']['контекст']),
        'основания_разбора': р['вход']['основания_разбора'], 'версия': хэш(вход), 'полнота': True}
    требовать(р['вход']['план_sha256'] == хэш(выбор), 'Подмена сохранённого выбора плана')
    if с is None:
        требовать(в is None, 'Агрегатная квитанция без явного решения')
        return
    _поля(в, {'схема', 'версия', 'идентичность', 'контекст_sha256', 'контекст', 'вход', 'поля_обращения',
        'решение', 'основания', 'время', 'полный_повтор_основание', 'граница', 'sha256'})
    требовать(type(в['поля_обращения']) is dict and в['поля_обращения']
        and all(type(к) is str and _sha(ш) for к, ш in в['поля_обращения'].items())
        and set(р['покрытие']) == {е['ключ'] for е in р['состав']}, 'Неполная агрегатная квитанция')
    тело = {к: з for к, з in в.items() if к != 'sha256'}
    требовать(в['схема'] == 'fum.ревью-наблюдённой-версии.1' and в['sha256'] == хэш(тело)
        and в['контекст'] == р['вход']['контекст'] and в['контекст_sha256'] == внимание._контекст(в['контекст'])
        and в['идентичность'] == вход['идентичность'] and в['вход'] == вход and в['версия'] == хэш(вход)
        and в['граница'] == 'Запись решения оператора; не доказательство адекватности, принятия или выполнения.',
        'Подмена агрегатной квитанции покрытия')
    внимание._время(в['время']); _строки(в['основания'])
    требовать(в['решение'] in {'рекомендовано', 'отложено', 'отклонено'}, 'Неверное агрегатное решение')
    if 'переиспользовать_sha256' in с:
        требовать(в['sha256'] == с['переиспользовать_sha256'], 'Подмена выбранного прежнего ревью')
    else:
        требовать(в['время'] == р['вход']['время'] and all(в[к] == с[к] for к in с),
            'Агрегатная квитанция расходится с вводом оператора')


def _единицы(состояние, номер, основания_разбора):
    запись = состояние['обращения'].get(номер)
    if запись is None:
        return []
    родитель = запись['идентичность']
    части = [(родитель['тип'], str(родитель['id']), запись['текущее_обращение'])]
    части += [('комментарий', и, о) for и, о in sorted(запись['текущие_комментарии'].items())]
    единицы = []
    for тип, идентификатор, версия in части:
        объект = {'репозиторий': состояние['репозиторий'], 'родитель': copy.deepcopy(родитель),
            'тип': тип, 'id': идентификатор, 'версия_sha256': версия['sha256'],
            'страница_sha256': версия['страница_sha256'], 'наблюдение': copy.deepcopy(версия['наблюдение'])}
        хэш_оснований = хэш(_основания(основания_разбора, _метка(объект)))
        единицы.append({'ключ': _ключ(объект, состояние['контекст_sha256'], хэш_оснований),
            'объект': объект, 'контекст_sha256': состояние['контекст_sha256'],
            'основания_sha256': хэш_оснований})
    return единицы


def _проверить_вход(вход):
    _поля(вход, {'схема', 'номер', 'план_sha256', 'контекст', 'основания_разбора',
        'время', 'происхождение', 'решения', 'суммарное'})
    требовать(вход['схема'] == 'fum.решение-разбора-обсуждения.1'
        and type(вход['номер']) is str and re.fullmatch('[1-9][0-9]*', вход['номер'])
        and type(вход['план_sha256']) is str and re.fullmatch('[0-9a-f]{64}', вход['план_sha256']),
        'Неверная версия входа или выбранного плана')
    внимание._контекст(вход['контекст']); внимание._время(вход['время'])
    _основания(вход['основания_разбора'], '')
    требовать(type(вход['происхождение']) is dict and вход['происхождение'], 'Нужно явное происхождение решения')
    требовать(type(вход['решения']) is list, 'Нужен конечный список решений')
    ключи = set()
    for р in вход['решения']:
        _поля(р, {'ключ', 'решение', 'основания', 'свидетельства'})
        требовать(type(р['ключ']) is str and re.fullmatch('[0-9a-f]{64}', р['ключ'])
            and р['ключ'] not in ключи, 'Повторный или неверный объект решения')
        ключи.add(р['ключ'])
        требовать(р['решение'] in {'рекомендовано', 'отложено', 'отклонено'}, 'Нужно решение оператора')
        _строки(р['основания']); _строки(р['свидетельства'])
    с = вход['суммарное']
    if с is not None:
        if type(с) is dict and set(с) == {'переиспользовать_sha256'}:
            требовать(type(с['переиспользовать_sha256']) is str
                and re.fullmatch('[0-9a-f]{64}', с['переиспользовать_sha256']), 'Нужен точный выбор прежнего ревью')
        else:
            _поля(с, {'решение', 'основания', 'полный_повтор_основание'})
            требовать(с['решение'] in {'рекомендовано', 'отложено', 'отклонено'}, 'Нужно явное суммарное решение')
            _строки(с['основания'])
            требовать(с['полный_повтор_основание'] is None or
                type(с['полный_повтор_основание']) is str and с['полный_повтор_основание'].strip(),
                'Нужно содержательное основание повторного агрегатного ревью')
    байты(вход)


def _прочитать_покрытия(каталог):
    записи = {}; решения = {}
    if not каталог.exists():
        return записи, решения
    for файл in sorted(каталог.iterdir()):
        if файл.name == '.lock':
            _прочитать_файл(файл)
            continue
        требовать(re.fullmatch(r'[0-9a-f]{64}\.json', файл.name), 'Неизвестный остаток покрытия')
        сырые = _прочитать_файл(файл); р = внимание._декодировать(сырые)
        _поля(р, {'схема', 'репозиторий', 'вход', 'состав', 'решения', 'покрытие', 'ревью',
            'ожидаемое_внимание_sha256'})
        требовать(р['схема'] == 'fum.покрытие-разбора-обсуждения.1'
            and файл.stem == хэш(р) and сырые == байты(р), 'Повреждено неизменяемое покрытие')
        _проверить_вход(р['вход'])
        требовать(р['ожидаемое_внимание_sha256'] is None or type(р['ожидаемое_внимание_sha256']) is str
            and re.fullmatch('[0-9a-f]{64}', р['ожидаемое_внимание_sha256']), 'Неверный ожидаемый SHA внимания')
        требовать(type(р['состав']) is list and type(р['решения']) is list and type(р['покрытие']) is dict,
            'Неверный состав покрытия')
        состав = {}
        for е in р['состав']:
            _проверить_единицу(е, р)
            требовать(е['ключ'] not in состав, 'Повтор единицы состава')
            состав[е['ключ']] = е
        выбранные = {з['ключ']: з for з in р['вход']['решения']}
        требовать(len(выбранные) == len(р['решения']), 'Потеря выбранного решения')
        собственные = set()
        for з in р['решения']:
            _поля(з, {'единица', 'решение', 'основания', 'свидетельства', 'время', 'происхождение'})
            к = з['единица']['ключ']
            требовать(к not in собственные and к in состав and з['единица'] == состав[к] and к in выбранные
                and all(з[п] == выбранные[к][п] for п in ('решение', 'основания', 'свидетельства'))
                and з['время'] == р['вход']['время'] and з['происхождение'] == р['вход']['происхождение'],
                'Подмена исходного решения оператора')
            собственные.add(к)
            требовать(к not in решения or решения[к] == з, 'Противоречащие покрытия одной версии')
            решения[к] = з
        требовать(set(р['покрытие']) <= set(состав), 'Покрытие вне выбранного состава')
        требовать(собственные == set(выбранные), 'Потеря выбранного объекта')
        _проверить_ревью(р)
        записи[файл.stem] = р
    for р in записи.values():
        требовать(all(к in решения and хэш(решения[к]) == ш for к, ш in р['покрытие'].items()),
            'Потеря или подмена свидетельства покрытия')
    return записи, решения


def _прочитать_исходники(корень, репозиторий):
    база = внимание._путь(корень / 'Issues' / репозиторий)
    папка = внимание._путь(база / 'наблюдения')
    страницы = {}; наблюдения = {}; родители = {}; порядки = set(); архиватор = внимание._архиватор()
    метаданные = []
    for файл in sorted(папка.glob('*/наблюдение.json')):
        сырые = _прочитать_файл(файл); н = внимание._декодировать(сырые)
        требовать(type(н) is dict, 'Метаданные наблюдения должны быть объектом')
        требовать(н.get('схема') == 'fum.наблюдение-обсуждений-GitHub.1' and н.get('репозиторий') == репозиторий
            and type(н.get('порядок')) is int and н['порядок'] > 0 and н['порядок'] not in порядки
            and type(н.get('полнота')) is bool and н.get('метка') == файл.parent.name
            and re.fullmatch(r'[\w.-]{1,160}', н['метка']) and н['метка'] not in {'.', '..'}
            and type(н.get('страницы')) is list and type(н.get('связи')) is dict
            and all(type(с) is list and all(type(ч) is str for ч in с) for с in н['связи'].values()),
            'Неверные метаданные наблюдения')
        внимание._время(н['время']); порядки.add(н['порядок'])
        метаданные.append((н, hashlib.sha256(сырые).hexdigest()))
    for н, шн in sorted(метаданные, key=lambda п: п[0]['порядок']):
        виденные = set(); состав = {}
        for п in н['страницы']:
            требовать(type(п) is dict and п.get('тип') in {'issues', 'comments'} and _sha(п.get('sha256'))
                and type(п.get('байты')) is int and п['байты'] >= 0, 'Неверная страница наблюдения')
            ключ = (п['тип'], п['sha256'])
            if ключ not in страницы:
                сырые = _прочитать_файл(база / 'данные' / (п['sha256'] + '.json'))
                требовать(hashlib.sha256(сырые).hexdigest() == п['sha256'], 'Подмена исходных байтов страницы')
                страницы[ключ] = (len(сырые), архиватор._проверить_записи(п['тип'], сырые, репозиторий))
            длина, объекты = страницы[ключ]
            требовать(длина == п['байты'], 'Подмена длины исходной страницы')
            for о in объекты:
                идентификатор = (п['тип'], о['id'])
                требовать(идентификатор not in виденные, 'Неоднозначный ID в одном наблюдении')
                виденные.add(идентификатор); состав[идентификатор] = о
                if п['тип'] == 'issues':
                    и = {'репозиторий': репозиторий, 'номер': str(о['number']), 'id': о['id'],
                        'тип': 'PR' if 'pull_request' in о else 'Issue'}
                    требовать(и['номер'] not in родители or родители[и['номер']] == и, 'Смена идентичности родителя')
                    родители[и['номер']] = и
        наблюдения[шн] = {'источник': {'метка': н['метка'], 'порядок': н['порядок'], 'время': н['время'], 'sha256': шн},
            'страницы': {(п['тип'], п['sha256']) for п in н['страницы']}, 'родители': copy.deepcopy(родители)}
    return наблюдения, страницы


def _источники(исходники, репозиторий, записи):
    наблюдения, страницы = исходники
    for запись in записи.values():
        требовать(запись['репозиторий'] == репозиторий, 'Покрытие другого репозитория')
        for е in запись['состав']:
            о = е['объект']; н = о['наблюдение']; найденное = наблюдения.get(н['sha256'])
            требовать(найденное is not None and н == найденное['источник']
                and найденное['родители'].get(о['родитель']['номер']) == о['родитель'], 'Подмена источника или родителя')
            тип = 'comments' if о['тип'] == 'комментарий' else 'issues'
            ключ = (тип, о['страница_sha256'])
            требовать(ключ in найденное['страницы'], 'Страница не принадлежит наблюдению')
            найденные = [ч for ч in страницы[ключ][1] if str(ч['id']) == о['id']]
            требовать(len(найденные) == 1 and хэш(найденные[0]) == о['версия_sha256'],
                'Версия объекта не подтверждена исходной страницей')
            ч = найденные[0]
            номер = ч['issue_url'].rsplit('/', 1)[1] if тип == 'comments' else str(ч['number'])
            требовать(номер == о['родитель']['номер'], 'Подмена номера родителя')
            if тип == 'issues' and запись['ревью'] is not None:
                требовать(запись['ревью']['поля_обращения'] == {к: хэш(з) for к, з in ч.items()},
                    'Агрегатное ревью не связано с полями исходного обращения')


def _есть_ревью(состояние, ревью):
    if ревью is None:
        return False
    запись = состояние['обращения'].get(ревью['идентичность']['номер'])
    return запись is not None and any(р == ревью for р in запись['ревью'])


def _снять(корень, репозиторий, каталог_внимания, каталог_покрытий, номер,
           контекст, основания_разбора, сейчас):
    а, п = _каталоги(каталог_внимания, каталог_покрытий)
    корень = внимание._путь(корень)
    требовать(type(номер) is str and re.fullmatch('[1-9][0-9]*', номер), 'Нужен точный номер обсуждения')
    _основания(основания_разбора, '')
    старое, ожидаемый = внимание._загрузить_с_хэшем(а, репозиторий)
    записи, решения = _прочитать_покрытия(п)
    try:
        исходники = _прочитать_исходники(корень, репозиторий)
    except (OSError, ValueError, TypeError, KeyError):
        исходники = None
    try:
        состояние = внимание.сверить(корень, репозиторий, старое, контекст, сейчас)
    except AttributeError as ошибка:
        raise ValueError('Неверный формат метаданных архива; внимание не погашено') from ошибка
    полнота = исходники is not None and состояние['сбор']['состояние'] == 'наблюдено' and состояние['сбор']['полнота']
    try:
        if исходники is not None:
            _источники(исходники, репозиторий, записи)
    except (OSError, ValueError, TypeError, KeyError):
        полнота = False
    единицы = _единицы(состояние, номер, основания_разбора)
    применённые = {и: р for и, р in записи.items() if _есть_ревью(старое, р['ревью'])}
    подтверждённые = {к: ш for р in применённые.values() for к, ш in р['покрытие'].items()}
    несогласованные = [и for и, р in записи.items() if и not in применённые and
        (р['ревью'] is not None or not all(подтверждённые.get(з['единица']['ключ']) == хэш(з) for з in р['решения']))]
    переиспользованы = [е for е in единицы if е['ключ'] in решения] if полнота else []
    остаток = [е for е in единицы if е not in переиспользованы]
    выбор = {'репозиторий': репозиторий, 'номер': номер, 'состав': единицы,
        'контекст_sha256': состояние['контекст_sha256'], 'основания_разбора': основания_разбора,
        'версия': состояние['обращения'].get(номер, {}).get('ключ_версии'), 'полнота': полнота}
    прежний = внимание.остаток(состояние)
    результат = {'схема': 'fum.план-разбора-обсуждения.1', 'выбор_sha256': хэш(выбор),
        'контекст_sha256': состояние['контекст_sha256'], 'полнота': полнота,
        'единицы': остаток, 'переиспользованы': переиспользованы,
        'несогласованные': sorted(несогласованные), 'прежний_остаток': прежний,
        'решения': решения, 'внимание': bool(not полнота or not единицы or остаток or несогласованные or прежний['сигналы']),
        'граница': 'Составное внимание нового CLI; прежний API не получает пообъектной гарантии.'}
    return результат, состояние, ожидаемый, записи, решения, единицы


def план(корень, репозиторий, каталог_внимания, каталог_покрытий, номер,
         контекст, основания_разбора, сейчас, *, полный=False):
    результат, _, _, _, _, единицы = _снять(корень, репозиторий, каталог_внимания,
        каталог_покрытий, номер, контекст, основания_разбора, сейчас)
    if полный:
        результат['единицы'] = единицы
    return результат


def прочитать(корень, репозиторий, каталог_внимания, каталог_покрытий, номер,
             контекст, основания_разбора, сейчас):
    результат, _, _, записи, _, _ = _снять(корень, репозиторий, каталог_внимания,
        каталог_покрытий, номер, контекст, основания_разбора, сейчас)
    return {**результат, 'покрытия': записи}


def _установить(каталог, запись):
    if not каталог.exists():
        каталог.mkdir(mode=0o700, exist_ok=True); внимание._синхронизировать(каталог.parent)
    замок = os.open(каталог / '.lock', os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    временный = None
    try:
        fcntl.flock(замок, fcntl.LOCK_EX)
        прежние, решения = _прочитать_покрытия(каталог)
        имя = хэш(запись); файл = каталог / (имя + '.json')
        if имя in прежние:
            требовать(прежние[имя] == запись, 'Противоречащий повтор покрытия')
            return False
        for з in запись['решения']:
            требовать(з['единица']['ключ'] not in решения, 'Конкурирующее решение той же версии')
        д, имя_временного = tempfile.mkstemp(prefix='.установка-', dir=каталог)
        временный = Path(имя_временного)
        with os.fdopen(д, 'wb') as поток:
            поток.write(байты(запись)); поток.flush(); os.fsync(поток.fileno())
        os.replace(временный, файл); временный = None; внимание._синхронизировать(каталог)
        return True
    finally:
        if временный is not None:
            временный.unlink(missing_ok=True)
        os.close(замок)


def _согласовать(корень, репозиторий, а, п, запись):
    вход = запись['вход']; ревью = запись['ревью']
    результат, состояние, ожидаемый, _, _, единицы = _снять(корень, репозиторий, а, п,
        вход['номер'], вход['контекст'], вход['основания_разбора'], вход['время'])
    if ревью is None or _есть_ревью(состояние, ревью):
        return False
    требовать(ожидаемый == запись['ожидаемое_внимание_sha256'],
        'Состояние внимания изменилось после выбора; сохранённый SHA не переизбирается')
    if not результат['полнота'] or единицы != запись['состав']:
        return False
    текущая = состояние['обращения'][вход['номер']]
    требовать(текущая['ключ_версии'] == ревью['версия'], 'Изменилась версия агрегатного входа')
    прежнее = текущая['применимое_ревью']
    требовать(прежнее is None or вход['суммарное'].get('полный_повтор_основание'),
        'Чужое применимое ревью не разрешает автоматический повтор')
    с = внимание.записать_ревью(состояние, вход['номер'], ревью['версия'], ревью['контекст_sha256'],
        ревью['решение'], ревью['основания'], ревью['время'],
        полный_повтор_основание=ревью['полный_повтор_основание'])
    требовать(с['обращения'][вход['номер']]['ревью'][-1] == ревью, 'Не совпала сохранённая агрегатная квитанция')
    return внимание.сохранить(а, с, ожидаемый_sha256=запись['ожидаемое_внимание_sha256'])


def решение(корень, репозиторий, каталог_внимания, каталог_покрытий, вход):
    _проверить_вход(вход)
    а, п = _каталоги(каталог_внимания, каталог_покрытий)
    данные = _снять(корень, репозиторий, а, п, вход['номер'], вход['контекст'],
        вход['основания_разбора'], вход['время'])
    результат, состояние, ожидаемый, записи, решения, единицы = данные
    прежние = [р for р in записи.values() if р['вход'] == вход]
    требовать(len(прежние) <= 1, 'Повторяющиеся неизменяемые намерения')
    if прежние:
        запись = прежние[0]
        изменено = _согласовать(корень, репозиторий, а, п, запись)
        return {'схема': 'fum.результат-разбора-обсуждения.1', 'покрытие_sha256': хэш(запись),
            'записано': изменено, 'повтор': True}
    требовать(результат['полнота'] and единицы and результат['выбор_sha256'] == вход['план_sha256'],
        'Неполный, неизвестный или устаревший выбранный состав')
    по_ключу = {е['ключ']: е for е in единицы}
    новые = []
    for р in вход['решения']:
        к = р['ключ']
        требовать(к in по_ключу and к not in решения, 'Лишнее или уже рассмотренное решение')
        новые.append({'единица': по_ключу[к], **{п: copy.deepcopy(р[п]) for п in ('решение', 'основания', 'свидетельства')},
            'время': вход['время'], 'происхождение': copy.deepcopy(вход['происхождение'])})
    все = {**решения, **{з['единица']['ключ']: з for з in новые}}
    покрытие = {е['ключ']: хэш(все[е['ключ']]) for е in единицы if е['ключ'] in все}
    ревью = None; суммарное = вход['суммарное']
    if суммарное is not None:
        требовать(set(покрытие) == set(по_ключу), 'Суммарная оценка требует полного пообъектного покрытия')
        обсуждение = состояние['обращения'][вход['номер']]
        if 'переиспользовать_sha256' in суммарное:
            найденные = [р for р in обсуждение['ревью'] if р['sha256'] == суммарное['переиспользовать_sha256']
                and р['версия'] == обсуждение['ключ_версии'] and р['контекст_sha256'] == состояние['контекст_sha256']]
            требовать(len(найденные) == 1, 'Выбранное прежнее ревью неприменимо')
            ревью = copy.deepcopy(найденные[0])
        else:
            с = внимание.записать_ревью(состояние, вход['номер'], обсуждение['ключ_версии'],
                состояние['контекст_sha256'], суммарное['решение'], суммарное['основания'], вход['время'],
                полный_повтор_основание=суммарное['полный_повтор_основание'])
            ревью = с['обращения'][вход['номер']]['ревью'][-1]
    требовать(новые or ревью is not None, 'Пустое новое намерение')
    запись = {'схема': 'fum.покрытие-разбора-обсуждения.1', 'репозиторий': репозиторий,
        'вход': copy.deepcopy(вход), 'состав': единицы, 'решения': новые, 'покрытие': покрытие, 'ревью': ревью,
        'ожидаемое_внимание_sha256': ожидаемый}
    записано = _установить(п, запись)
    изменено = _согласовать(корень, репозиторий, а, п, запись)
    return {'схема': 'fum.результат-разбора-обсуждения.1', 'покрытие_sha256': хэш(запись),
        'записано': записано or изменено, 'повтор': False}



def построить_разбор() -> argparse.ArgumentParser:
    разбор = argparse.ArgumentParser(allow_abbrev=False)
    команды = разбор.add_subparsers(dest="команда", required=True)

    план = команды.add_parser("план", allow_abbrev=False)
    добавить_общие_параметры(план)
    план.add_argument("--симптом-json", dest="сырой_симптом", required=True)
    план.add_argument("--идентификатор-попытки", required=True)

    состояние = команды.add_parser("состояние", allow_abbrev=False)
    добавить_общие_параметры(состояние)

    резерв = команды.add_parser("зарезервировать", allow_abbrev=False)
    добавить_общие_параметры(резерв)
    резерв.add_argument("--симптом-json", dest="сырой_симптом", required=True)
    добавить_ограждения(резерв)
    добавить_создателя(резерв)

    for имя in ("начать-вызов-среды", "освободить"):
        команда = команды.add_parser(имя, allow_abbrev=False)
        добавить_общие_параметры(команда)
        добавить_ограждения(команда)
        добавить_создателя(команда)

    подтверждение = команды.add_parser("подтвердить-создание", allow_abbrev=False)
    добавить_общие_параметры(подтверждение)
    добавить_ограждения(подтверждение)
    добавить_создателя(подтверждение)

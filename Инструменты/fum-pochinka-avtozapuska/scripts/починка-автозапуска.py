class ОшибкаКонтракта(RuntimeError):
    """Ошибка входа или локального контекста без публичного JSON-результата."""


class ОшибкаОграждения(RuntimeError):
    """Ожидаемый отказ состояния с безопасным машиночитаемым результатом."""

    def __init__(сам, состояние: str, сообщение: str) -> None:
        super().__init__(сообщение)
        сам.состояние = состояние


def чистая_среда_системы_версий() -> dict[str, str]:
    среда = {
        ключ: значение
        for ключ, значение in os.environ.items()
        if not ключ.upper().startswith("GIT_")
    }
    среда["GIT_NO_REPLACE_OBJECTS"] = "1"
    среда["GIT_OPTIONAL_LOCKS"] = "0"
    return среда


def выполнить_команду_системы_версий(
    корень: Path,
    аргументы: list[str],
    *,
    вход: bytes | None = None,
    проверять: bool = True,
) -> subprocess.CompletedProcess[bytes]:
    try:
        результат = subprocess.run(
            ["git", "-C", str(корень), *аргументы],
            input=вход,
            capture_output=True,
            check=False,
            env=чистая_среда_системы_версий(),
            timeout=ПРЕДЕЛ_ОЖИДАНИЯ_КОМАНДЫ,
        )
    except (OSError, subprocess.TimeoutExpired) as ошибка:
        raise ОшибкаКонтракта(f"Не удалось выполнить Git: {ошибка}") from ошибка
    if проверять and результат.returncode != 0:
        пояснение = результат.stderr.decode("utf-8", errors="replace").strip()
        raise ОшибкаКонтракта(
            "Git-команда завершилась с ошибкой"
            + (f": {пояснение}" if пояснение else ".")
        )
    return результат


def текст_результата_системы_версий(
    результат: subprocess.CompletedProcess[bytes],
) -> str:
    try:
        return результат.stdout.decode("utf-8", errors="strict").strip()
    except UnicodeDecodeError as ошибка:
        raise ОшибкаКонтракта("Git вернул не-UTF-8 результат.") from ошибка


def разрешить_контекст(указанный_корень: Path) -> tuple[Path, str, str]:
    кандидат = указанный_корень.expanduser().resolve()
    if not кандидат.is_dir():
        raise ОшибкаКонтракта("Корень рабочей копии не существует.")
    вершина_корня = Path(
        текст_результата_системы_версий(
            выполнить_команду_системы_версий(
                кандидат,
                ["rev-parse", "--show-toplevel"],
            )
        )
    ).resolve()
    if вершина_корня != кандидат:
        raise ОшибкаКонтракта(
            "Нужно передать точный корень текущей Git-рабочей копии."
        )
    ветка_результат = выполнить_команду_системы_версий(
        кандидат,
        ["symbolic-ref", "--quiet", "HEAD"],
        проверять=False,
    )
    if ветка_результат.returncode != 0:
        raise ОшибкаКонтракта("Починка требует именованную локальную ветку.")
    ветка = текст_результата_системы_версий(ветка_результат)
    if not ветка.startswith("refs/heads/"):
        raise ОшибкаКонтракта("Текущая ссылка не является локальной веткой.")
    вершина = текст_результата_системы_версий(
        выполнить_команду_системы_версий(
            кандидат,
            ["rev-parse", "--verify", "HEAD"],
        )
    )
    return кандидат, ветка, вершина


def разобрать_без_повторов(
    сырой_текст: str,
    название: str = "Симптом",
) -> object:
    def собрать(пары: list[tuple[str, object]]) -> dict[str, object]:
        результат: dict[str, object] = {}
        for ключ, значение in пары:
            if ключ in результат:
                raise ОшибкаКонтракта(
                    f"{название}: поле {ключ!r} повторено."
                )
            результат[ключ] = значение
        return результат

    try:
        return json.loads(сырой_текст, object_pairs_hook=собрать)
    except ОшибкаКонтракта:
        raise
    except (json.JSONDecodeError, UnicodeError) as ошибка:
        raise ОшибкаКонтракта(
            f"{название} должно быть корректным JSON."
        ) from ошибка


def проверить_однострочное(
    значение: object,
    название: str,
    *,
    предел: int = 1024,
) -> str:
    if (
        not isinstance(значение, str)
        or not значение
        or значение != значение.strip()
        or len(значение) > предел
        or any(ord(знак) < 32 or ord(знак) == 127 for знак in значение)
    ):
        raise ОшибкаКонтракта(
            f"{название} должно быть непустой безопасной однострочной строкой."
        )
    return значение


def разобрать_канонический_идентификатор(
    значение: object,
    название: str,
) -> tuple[str, uuid.UUID]:
    строка = проверить_однострочное(значение, название, предел=64)
    try:
        разобранный = uuid.UUID(строка)
    except (ValueError, AttributeError) as ошибка:
        raise ОшибкаКонтракта(f"{название} должно быть UUID.") from ошибка
    if str(разобранный) != строка:
        raise ОшибкаКонтракта(f"{название} должно быть каноническим UUID.")
    return строка, разобранный


def проверить_идентификатор_четвёртой_версии(
    значение: object,
    название: str,
) -> str:
    строка, разобранный = разобрать_канонический_идентификатор(
        значение,
        название,
    )
    if разобранный.version != 4:
        raise ОшибкаКонтракта(f"{название} должно быть каноническим UUIDv4.")
    return строка


def проверить_идентификатор_задачи(значение: object, название: str) -> str:
    строка, разобранный = разобрать_канонический_идентификатор(
        значение,
        название,
    )
    if разобранный.version not in {4, 7}:
        raise ОшибкаКонтракта(
            f"{название} должно быть каноническим UUIDv4 или UUIDv7."
        )
    return строка


def проверить_симптом(сырой_текст: str) -> dict[str, object]:
    значение = разобрать_без_повторов(сырой_текст)
    if not isinstance(значение, dict):
        raise ОшибкаКонтракта("Симптом должен быть JSON-объектом.")
    if set(значение) != {"версия", "код", "описание"}:
        raise ОшибкаКонтракта("Симптом содержит неизвестные или отсутствующие поля.")
    if type(значение["версия"]) is not int or значение["версия"] != 1:
        raise ОшибкаКонтракта("Поддерживается только версия симптома 1.")
    if значение["код"] != "автозапуск_не_срабатывает":
        raise ОшибкаКонтракта("Неизвестен код симптома починки автозапуска.")
    описание = проверить_однострочное(
        значение["описание"],
        "Описание симптома",
        предел=500,
    )
    опасные_фрагменты = (
        "file://",
        "$" + "HOME",
        "${",
        chr(126) + "/",
        chr(126) + "\\",
        "\\\\",
    )
    if (
        ШАБЛОН_НЕПРОЗРАЧНОГО_ИДЕНТИФИКАТОРА.search(описание)
        or any(фрагмент in описание for фрагмент in опасные_фрагменты)
        or "/" in описание
        or "\\" in описание
    ):
        raise ОшибкаКонтракта(
            "Описание симптома не должно содержать локальные пути или непрозрачные ID."
        )
    return {
        "версия": 1,
        "код": "автозапуск_не_срабатывает",
        "описание": описание,
    }


def проверить_состояние_починки(значение: object) -> dict[str, object]:
    if not isinstance(значение, dict):
        raise ОшибкаКонтракта("Ссылка починки должна содержать JSON-объект.")
    обязательные = {
        "схема",
        "состояние",
        "ветка",
        "исходная_вершина",
        "хэш_промпта",
        "ключ_починки",
        "симптом",
        "идентификатор_попытки",
        "создатель",
        "свидетельство_среды",
        "исполнитель",
        "исход",
        "обновлено_utc",
    }
    допустимые = обязательные | {"коммит"}
    неизвестные = sorted(set(значение) - допустимые)
    отсутствуют = sorted(обязательные - set(значение))
    if неизвестные:
        raise ОшибкаКонтракта(
            "Состояние починки содержит неизвестные поля: "
            + ", ".join(неизвестные)
        )
    if отсутствуют:
        raise ОшибкаКонтракта(
            "В состоянии починки отсутствуют поля: " + ", ".join(отсутствуют)
        )
    if значение["схема"] != СХЕМА:
        raise ОшибкаКонтракта("Ссылка починки содержит неизвестную схему.")
    фаза = значение["состояние"]
    if фаза not in {
        "зарезервирован",
        "вызов_мог_состояться",
        "задача_создана",
        "исполнитель_связан",
        "исполнитель_подтверждён",
        "завершён",
    }:
        raise ОшибкаКонтракта("Состояние починки содержит неизвестную фазу.")
    ветка = проверить_однострочное(значение["ветка"], "Ветка")
    if not ветка.startswith("refs/heads/"):
        raise ОшибкаКонтракта("Состояние починки содержит не локальную ветку.")
    if not isinstance(значение["исходная_вершина"], str) or not ШАБЛОН_ОБЪЕКТА.fullmatch(
        значение["исходная_вершина"]
    ):
        raise ОшибкаКонтракта("Исходная вершина починки некорректна.")
    for поле in ("хэш_промпта", "ключ_починки"):
        if not isinstance(значение[поле], str) or not ШАБЛОН_ХЭША.fullmatch(
            значение[поле]
        ):
            raise ОшибкаКонтракта(f"Поле {поле} содержит некорректный SHA-256.")
    проверить_симптом(json.dumps(значение["симптом"], ensure_ascii=False))
    проверить_идентификатор_четвёртой_версии(
        значение["идентификатор_попытки"],
        "Идентификатор попытки состояния",
    )
    создатель = значение["создатель"]
    if not isinstance(создатель, dict) or set(создатель) != {"задача", "поколение"}:
        raise ОшибкаКонтракта("Создатель починки имеет некорректную схему.")
    проверить_идентификатор_задачи(создатель["задача"], "Задача-создатель")
    проверить_идентификатор_четвёртой_версии(
        создатель["поколение"],
        "Поколение создателя",
    )
    свидетельство = значение["свидетельство_среды"]
    if свидетельство is not None:
        if not isinstance(свидетельство, dict):
            raise ОшибкаКонтракта("Свидетельство среды имеет некорректный тип.")
        if свидетельство.get("вид") == "clientThreadId":
            if set(свидетельство) != {"вид", "значение"}:
                raise ОшибкаКонтракта("Свидетельство clientThreadId повреждено.")
            проверить_однострочное(свидетельство["значение"], "clientThreadId")
        elif свидетельство.get("вид") == "threadId":
            if set(свидетельство) != {"вид", "threadId", "hostId"}:
                raise ОшибкаКонтракта("Свидетельство threadId повреждено.")
            проверить_однострочное(свидетельство["threadId"], "threadId")
            проверить_однострочное(свидетельство["hostId"], "hostId")
        else:
            raise ОшибкаКонтракта("Свидетельство среды содержит неизвестный вид.")
    исполнитель = значение["исполнитель"]
    if исполнитель is not None:
        if not isinstance(исполнитель, dict) or set(исполнитель) not in (
            {"задача", "поколение"},
            {"задача", "поколение", "базовая_вершина"},
        ):
            raise ОшибкаКонтракта("Исполнитель починки имеет некорректную схему.")
        проверить_идентификатор_задачи(исполнитель["задача"], "Задача-исполнитель")
        if исполнитель["поколение"] is not None:
            проверить_идентификатор_четвёртой_версии(
                исполнитель["поколение"],
                "Поколение исполнителя",
            )
        if "базовая_вершина" in исполнитель and (
            not isinstance(исполнитель["базовая_вершина"], str)
            or not ШАБЛОН_ОБЪЕКТА.fullmatch(исполнитель["базовая_вершина"])
        ):
            raise ОшибкаКонтракта("Базовая вершина исполнителя некорректна.")
        if исполнитель["задача"] == создатель["задача"]:
            raise ОшибкаКонтракта(
                "Исполнитель починки должен быть отдельной задачей."
            )
        if "базовая_вершина" in исполнитель:
            if исполнитель["поколение"] is None:
                raise ОшибкаКонтракта(
                    "Подтверждённый исполнитель не содержит поколения."
                )
            if исполнитель["базовая_вершина"] != значение["исходная_вершина"]:
                raise ОшибкаКонтракта(
                    "Базовая вершина исполнителя не совпадает с планом."
                )
        elif исполнитель["поколение"] is not None:
            raise ОшибкаКонтракта(
                "Неподтверждённый исполнитель не может содержать поколение."
            )
    ранние_фазы = {"зарезервирован", "вызов_мог_состояться", "задача_создана"}
    if фаза in ранние_фазы and исполнитель is not None:
        raise ОшибкаКонтракта("Ранняя фаза не может содержать исполнителя.")
    if фаза in {"зарезервирован", "вызов_мог_состояться"} and свидетельство is not None:
        raise ОшибкаКонтракта("Фаза до подтверждения не содержит свидетельства среды.")
    if фаза == "задача_создана" and свидетельство is None:
        raise ОшибкаКонтракта("Созданная задача не содержит свидетельства среды.")
    if фаза == "исполнитель_связан" and (
        not isinstance(исполнитель, dict)
        or set(исполнитель) != {"задача", "поколение"}
        or исполнитель["поколение"] is not None
    ):
        raise ОшибкаКонтракта("Связанный исполнитель имеет неверную форму.")
    if фаза == "исполнитель_подтверждён" and (
        not isinstance(исполнитель, dict)
        or set(исполнитель) != {"задача", "поколение", "базовая_вершина"}
    ):
        raise ОшибкаКонтракта("Подтверждённый исполнитель имеет неверную форму.")
    исход = значение["исход"]
    if фаза != "завершён":
        if исход is not None or "коммит" in значение:
            raise ОшибкаКонтракта("Незавершённая фаза содержит итог починки.")
    elif исход == "коммит_подтверждён":
        if not isinstance(исполнитель, dict) or set(исполнитель) != {
            "задача",
            "поколение",
            "базовая_вершина",
        }:
            raise ОшибкаКонтракта(
                "Подтверждение коммита требует подтверждённого исполнителя."
            )
        if "коммит" not in значение or not isinstance(
            значение["коммит"], str
        ) or not ШАБЛОН_ОБЪЕКТА.fullmatch(значение["коммит"]):
            raise ОшибкаКонтракта(
                "У подтверждённого коммита отсутствует точный объект."
            )
    elif исход == "неподтверждён":
        if not isinstance(исполнитель, dict):
            raise ОшибкаКонтракта("Неподтверждённый исход требует исполнителя.")
        if "коммит" in значение:
            raise ОшибкаКонтракта("Неподтверждённый исход не публикует коммит.")
    else:
        raise ОшибкаКонтракта("Завершённая починка содержит неизвестный исход.")
    проверить_однострочное(значение["обновлено_utc"], "Время обновления")
    return значение


def канонические_байты(значение: object) -> bytes:
    return (
        json.dumps(
            значение,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        )
        + "\n"
    ).encode("utf-8")


def хэш(данные: bytes) -> str:
    return "sha256:" + hashlib.sha256(данные).hexdigest()


def прочитать_из_вершины(корень: Path, путь: str) -> bytes:
    результат = выполнить_команду_системы_версий(
        корень,
        ["show", f"HEAD:{путь}"],
        проверять=False,
    )
    if результат.returncode != 0:
        raise ОшибкаКонтракта(
            f"В точном HEAD отсутствует обязательный файл {путь}."
        )
    return результат.stdout


def построить_план(
    корень: Path,
    ветка: str,
    вершина: str,
    симптом: dict[str, object],
    попытка: str,
) -> dict[str, object]:
    байты_шаблона = прочитать_из_вершины(корень, ПУТЬ_ШАБЛОНА)
    try:
        шаблон = байты_шаблона.decode("utf-8", errors="strict")
    except UnicodeDecodeError as ошибка:
        raise ОшибкаКонтракта("Шаблон промпта должен быть UTF-8.") from ошибка
    начало_блока = "````text\n"
    конец_блока = "\n````"
    if шаблон.count(начало_блока) != 1:
        raise ОшибкаКонтракта("Шаблон должен содержать ровно один текстовый блок.")
    до_блока, остаток = шаблон.split(начало_блока, 1)
    if остаток.count(конец_блока) != 1:
        raise ОшибкаКонтракта("Текстовый блок шаблона должен быть закрыт ровно один раз.")
    содержимое, после_блока = остаток.split(конец_блока, 1)
    if not до_блока.strip() or not после_блока.strip():
        raise ОшибкаКонтракта("Шаблон должен сохранять описание и источники блока.")
    if содержимое.count(МАРКЕР_СРЕДЫ) != 1:
        raise ОшибкаКонтракта("Шаблон должен содержать ровно один FUM runtime-маркер.")
    публичный = содержимое.replace(МАРКЕР_СРЕДЫ, "").strip() + "\n"
    хэш_публичного_промпта = хэш(публичный.encode("utf-8"))
    ключ = хэш(
        канонические_байты(
            {
                "схема": СХЕМА,
                "ветка": ветка,
                "вершина": вершина,
                "хэш_промпта": хэш_публичного_промпта,
                "симптом": симптом,
            }
        )
    )
    конверт_среды = (
        "FUM-RUNTIME: не публиковать\n"
        f"- идентификатор попытки: `{попытка}`\n"
        f"- ключ починки: `{ключ}`\n"
        f"- исходная ветка: `{ветка}`\n"
        f"- исходная вершина: `{вершина}`\n"
        f"- хэш публичного промпта: `{хэш_публичного_промпта}`\n"
        "- идентификатор задачи: точный корневой `CODEX_THREAD_ID` этой дочерней задачи\n"
    )
    полный = (
        содержимое.replace(МАРКЕР_СРЕДЫ, конверт_среды.rstrip()).strip()
        + "\n"
    )
    return {
        "состояние": "запланирован",
        "ветка": ветка,
        "вершина": вершина,
        "хэш_промпта": хэш_публичного_промпта,
        "ключ_починки": ключ,
        "публичный_промпт": публичный,
        "промпт": полный,
        "симптом": симптом,
    }


def запустить_очередь(корень: Path, *аргументы: str) -> dict[str, object]:
    исходник = прочитать_из_вершины(корень, ПУТЬ_ОЧЕРЕДИ)
    try:
        код = исходник.decode("utf-8", errors="strict")
    except UnicodeDecodeError as ошибка:
        raise ОшибкаКонтракта("Исполнитель очереди в HEAD должен быть UTF-8.") from ошибка
    try:
        результат = subprocess.run(
            [
                sys.executable,
                "-c",
                код,
                *аргументы,
                "--repo-root",
                str(корень),
                "--json",
            ],
            cwd=корень,
            capture_output=True,
            check=False,
            text=True,
            env=чистая_среда_системы_версий(),
            timeout=ПРЕДЕЛ_ОЖИДАНИЯ_КОМАНДЫ,
        )
    except (OSError, subprocess.TimeoutExpired) as ошибка:
        raise ОшибкаКонтракта(f"Не удалось вызвать очередь: {ошибка}") from ошибка
    try:
        данные = json.loads(результат.stdout) if результат.stdout else {}
    except json.JSONDecodeError as ошибка:
        raise ОшибкаКонтракта("Очередь вернула некорректный JSON.") from ошибка
    if результат.returncode != 0 or not isinstance(данные, dict):
        сообщение = данные.get("message") if isinstance(данные, dict) else None
        raise ОшибкаКонтракта(
            str(сообщение or результат.stderr.strip() or "Очередь отклонила запрос.")
        )
    return данные


def состояние_очереди(корень: Path) -> tuple[dict[str, object], dict[str, object]]:
    снимок = запустить_очередь(корень, "status")
    ссылка = снимок.get("queue_ref")
    объект = снимок.get("queue_oid")
    if not isinstance(ссылка, str) or not isinstance(объект, str):
        raise ОшибкаКонтракта("У активной очереди отсутствует точный Git-снимок.")
    объект_содержимого = выполнить_команду_системы_версий(
        корень,
        ["cat-file", "blob", объект],
    )
    try:
        полное = json.loads(
            объект_содержимого.stdout.decode("utf-8", errors="strict")
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as ошибка:
        raise ОшибкаКонтракта("Git-ссылка очереди содержит некорректное состояние.") from ошибка
    if not isinstance(полное, dict):
        raise ОшибкаКонтракта("Git-ссылка очереди должна содержать JSON-объект.")
    return снимок, полное


def проверить_владельца(
    снимок: dict[str, object],
    задача: str,
    поколение: str | None,
) -> dict[str, object]:
    владелец = снимок.get("owner")
    if not isinstance(владелец, dict) or владелец.get("task_id") != задача:
        raise ОшибкаОграждения(
            "нет_владения_FIFO",
            "Текущая задача не является владельцем FIFO.",
        )
    if поколение is not None and владелец.get("generation") != поколение:
        raise ОшибкаОграждения(
            "чужое_поколение_FIFO",
            "Поколение владельца FIFO не совпало.",
        )
    return владелец


def рабочая_копия_грязна(корень: Path) -> bool:
    рабочее_дерево = выполнить_команду_системы_версий(
        корень,
        [
            "-c",
            "core.quotepath=false",
            "status",
            "--porcelain=v1",
            "-z",
            "--untracked-files=all",
            "--ignore-submodules=none",
            "--",
            ".",
            ":(top,exclude).obsidian",
            ":(top,exclude).obsidian/**",
        ],
    )
    индекс = выполнить_команду_системы_версий(
        корень,
        ["diff", "--cached", "--name-only", "-z", "--"],
    )
    return bool(рабочее_дерево.stdout or индекс.stdout)


def имя_ссылки_починки(снимок: dict[str, object], ветка: str) -> str:
    рабочее_дерево = снимок.get("worktree_id")
    if not isinstance(рабочее_дерево, str) or not re.fullmatch(
        r"[0-9a-f]{64}", рабочее_дерево
    ):
        raise ОшибкаКонтракта("Очередь вернула некорректный worktree_id.")
    ветка_хэш = hashlib.sha256(ветка.encode("utf-8")).hexdigest()
    return f"refs/fum/починка-автозапуска/{рабочее_дерево}/{ветка_хэш}"


def прочитать_ссылку(
    корень: Path,
    ссылка: str,
) -> tuple[dict[str, object] | None, str | None]:
    результат = выполнить_команду_системы_версий(
        корень,
        ["rev-parse", "--verify", "--quiet", ссылка],
        проверять=False,
    )
    if результат.returncode == 1:
        return None, None
    if результат.returncode != 0:
        raise ОшибкаКонтракта("Не удалось прочитать ссылку починки.")
    объект = текст_результата_системы_версий(результат)
    объект_содержимого = выполнить_команду_системы_версий(
        корень,
        ["cat-file", "blob", объект],
    )
    try:
        состояние = разобрать_без_повторов(
            объект_содержимого.stdout.decode("utf-8", errors="strict"),
            "Состояние починки",
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as ошибка:
        raise ОшибкаКонтракта("Ссылка починки содержит некорректный JSON.") from ошибка
    return проверить_состояние_починки(состояние), объект


def записать_объект_состояния(корень: Path, состояние: dict[str, object]) -> str:
    результат = выполнить_команду_системы_версий(
        корень,
        ["hash-object", "-w", "--stdin"],
        вход=канонические_байты(состояние),
    )
    return текст_результата_системы_версий(результат)


def время_всемирное() -> str:
    return datetime.now(tz=timezone.utc).isoformat(timespec="milliseconds").replace(
        "+00:00", "Z"
    )


def проверить_общие_ограждения(
    состояние: dict[str, object],
    аргументы: argparse.Namespace,
) -> None:
    соответствия = {
        "ветка": аргументы.ожидаемая_ветка,
        "исходная_вершина": аргументы.ожидаемая_вершина,
        "хэш_промпта": аргументы.ожидаемый_хэш_промпта,
        "ключ_починки": аргументы.ожидаемый_ключ_починки,
        "идентификатор_попытки": аргументы.идентификатор_попытки,
    }
    if any(состояние.get(ключ) != значение for ключ, значение in соответствия.items()):
        raise ОшибкаОграждения(
            "ограждение_не_совпало",
            "Снимок починки не совпал с переданными ограждениями.",
        )


def проверить_план_по_аргументам(
    план: dict[str, object],
    аргументы: argparse.Namespace,
) -> None:
    пары = (
        ("ветка", аргументы.ожидаемая_ветка),
        ("вершина", аргументы.ожидаемая_вершина),
        ("хэш_промпта", аргументы.ожидаемый_хэш_промпта),
        ("ключ_починки", аргументы.ожидаемый_ключ_починки),
    )
    if any(план[ключ] != ожидаемое for ключ, ожидаемое in пары):
        raise ОшибкаОграждения(
            "план_изменился",
            "Текущий точный план не совпал с ограждениями.",
        )


def транзакционно_изменить(
    корень: Path,
    ветка: str,
    роль: Callable[[dict[str, object], dict[str, object]], None],
    преобразование: Callable[
        [dict[str, object] | None], tuple[dict[str, object] | None, dict[str, object]]
    ],
) -> dict[str, object]:
    for номер in range(ЧИСЛО_ПОПЫТОК_СРАВНЕНИЯ):
        снимок, _ = состояние_очереди(корень)
        роль(снимок, _)
        if снимок.get("branch_ref") != ветка:
            raise ОшибкаОграждения("ветка_изменилась", "Текущая ветка изменилась.")
        владелец = снимок.get("owner")
        закреплённая_вершина = (
            владелец.get("base_head") if isinstance(владелец, dict) else None
        )
        if not isinstance(
            закреплённая_вершина,
            str,
        ) or not ШАБЛОН_ОБЪЕКТА.fullmatch(закреплённая_вершина):
            raise ОшибкаКонтракта(
                "У владельца FIFO отсутствует точная базовая вершина."
            )
        текущая_вершина = текст_результата_системы_версий(
            выполнить_команду_системы_версий(
                корень,
                ["rev-parse", "--verify", ветка],
            )
        )
        if текущая_вершина != закреплённая_вершина:
            raise ОшибкаОграждения(
                "вершина_FIFO_не_совпала",
                "Именованная ветка не совпадает с базовой вершиной владельца FIFO.",
            )
        ссылка_очереди = снимок["queue_ref"]
        объект_очереди = снимок["queue_oid"]
        if not isinstance(ссылка_очереди, str) or not isinstance(объект_очереди, str):
            raise ОшибкаКонтракта("Не удалось получить точный снимок очереди.")
        ссылка = имя_ссылки_починки(снимок, ветка)
        прежнее, прежний_объект = прочитать_ссылку(корень, ссылка)
        новое, результат = преобразование(copy.deepcopy(прежнее))
        строки = [
            "start",
            f"verify {ветка} {закреплённая_вершина}",
            f"verify {ссылка_очереди} {объект_очереди}",
        ]
        if новое == прежнее:
            ожидаемый_объект = прежний_объект or ("0" * len(закреплённая_вершина))
            строки.append(f"verify {ссылка} {ожидаемый_объект}")
        elif новое is None:
            if прежний_объект is None:
                строки.append(
                    f"verify {ссылка} {'0' * len(закреплённая_вершина)}"
                )
            else:
                строки.append(f"delete {ссылка} {прежний_объект}")
        else:
            новый_объект = записать_объект_состояния(корень, новое)
            if прежний_объект is None:
                строки.append(f"create {ссылка} {новый_объект}")
            else:
                строки.append(f"update {ссылка} {новый_объект} {прежний_объект}")
        строки.extend(["prepare", "commit", ""])
        запись = выполнить_команду_системы_версий(
            корень,
            ["update-ref", "--stdin"],
            вход="\n".join(строки).encode("utf-8"),
            проверять=False,
        )
        if запись.returncode == 0:
            return результат
        time.sleep(min(0.01 * (2**номер), 0.2))
    raise ОшибкаКонтракта("Не удалось атомарно обновить состояние починки.")



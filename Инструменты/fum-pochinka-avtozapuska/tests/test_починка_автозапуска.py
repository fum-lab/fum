ПУТЬ_ШАБЛОНА = Path(
    "Инструменты/fum-pochinka-avtozapuska/"
    "references/промпт-задачи-починки.md"
)
ПУТЬ_ОЧЕРЕДИ = Path(
    "Инструменты/fum-ocheredj-zadach-git-vetki/"
    "scripts/ocheredj-zadach-git-vetki.py"
)
ЗАДАЧА_СОЗДАТЕЛЯ = "0190abcd-0000-7000-8000-00000000000a"
ЗАДАЧА_ИСПОЛНИТЕЛЯ = "01900000-0000-7000-8000-000000000002"
ЗАДАЧА_ПОСРЕДНИКА = "01900000-0000-7000-8000-000000000003"

СИМПТОМ = {
    "версия": 1,
    "код": "автозапуск_не_срабатывает",
    "описание": "Плановые тики не создают следующую задачу.",
}


class ФикстураПочинкиАвтозапуска(unittest.TestCase):
    def __init__(сам, название_метода: str = "runTest") -> None:
        super().__init__(название_метода)
        сам.временный_каталог = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный_каталог.cleanup)
        сам.репозиторий = Path(сам.временный_каталог.name) / "репозиторий"
        сам.репозиторий.mkdir()
        сам.выполнить_команду_системы_версий("init", "-b", "master")
        сам.выполнить_команду_системы_версий("config", "user.name", "FUM Test")
        сам.выполнить_команду_системы_версий(
            "config",
            "user.email",
            "fum-test@example.invalid",
        )
        сам._скопировать(ПУТЬ_ОЧЕРЕДИ)
        сам._скопировать(ПУТЬ_ИНСТРУМЕНТА)
        сам._скопировать(ПУТЬ_ШАБЛОНА)
        (сам.репозиторий / "tracked.txt").write_text(
            "исходное состояние\n",
            encoding="utf-8",
        )
        сам.выполнить_команду_системы_версий("add", ".")
        сам.выполнить_команду_системы_версий(
            "commit",
            "-m",
            "Исходная фикстура",
        )

    def _скопировать(сам, путь: Path) -> None:
        источник = КОРЕНЬ_РЕПОЗИТОРИЯ / путь
        назначение = сам.репозиторий / путь
        назначение.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(источник, назначение)

    def выполнить_команду_системы_версий(
        сам,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            ["git", "-C", str(сам.репозиторий), *аргументы],
            check=True,
            capture_output=True,
            text=True,
        )

    def запустить(
        сам,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [
                sys.executable,
                str(сам.репозиторий / ПУТЬ_ИНСТРУМЕНТА),
                *аргументы,
                "--корень-рабочей-копии",
                str(сам.репозиторий),
                "--json",
            ],
            cwd=сам.репозиторий,
            check=False,
            capture_output=True,
            text=True,
            timeout=20,
        )

    def очередь(
        сам,
        *аргументы: str,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [
                sys.executable,
                str(сам.репозиторий / ПУТЬ_ОЧЕРЕДИ),
                *аргументы,
                "--repo-root",
                str(сам.репозиторий),
                "--json",
            ],
            cwd=сам.репозиторий,
            check=False,
            capture_output=True,
            text=True,
            timeout=20,
        )

    def данные(
        сам,
        результат: subprocess.CompletedProcess[str],
    ) -> dict[str, object]:
        сам.assertTrue(результат.stdout, результат.stderr)
        return json.loads(результат.stdout)

    def прочитать_состояние_починки(
        сам,
    ) -> tuple[str, dict[str, object]]:
        ссылка = сам.выполнить_команду_системы_версий(
            "for-each-ref",
            "--format=%(refname)",
            "refs/fum/починка-автозапуска/",
        ).stdout.strip()
        сам.assertTrue(ссылка)
        состояние = json.loads(
            сам.выполнить_команду_системы_версий(
                "cat-file",
                "blob",
                ссылка,
            ).stdout
        )
        сам.assertIsInstance(состояние, dict)
        return ссылка, состояние

    def записать_состояние_починки(
        сам,
        ссылка: str,
        состояние: dict[str, object],
    ) -> None:
        запись = subprocess.run(
            ["git", "-C", str(сам.репозиторий), "hash-object", "-w", "--stdin"],
            input=json.dumps(состояние, ensure_ascii=False),
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
        сам.выполнить_команду_системы_версий("update-ref", ссылка, запись)

    def допустить(сам, задача: str) -> dict[str, object]:
        результат = сам.очередь("join", "--task-id", задача)
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        данные = сам.данные(результат)
        сам.assertEqual(данные["state"], "admitted")
        return данные

    def план(сам, попытка: str = ПОПЫТКА) -> dict[str, object]:
        результат = сам.запустить(
            "план",
            "--симптом-json",
            json.dumps(СИМПТОМ, ensure_ascii=False),
            "--идентификатор-попытки",
            попытка,
        )
        сам.assertEqual(результат.returncode, 0, результат.stderr)
        return сам.данные(результат)

    def общие_ограждения(
        сам,
        план: dict[str, object],
        попытка: str = ПОПЫТКА,
    ) -> list[str]:
        return [
            "--ожидаемая-ветка",
            str(план["ветка"]),
            "--ожидаемая-вершина",
            str(план["вершина"]),
            "--ожидаемый-хэш-промпта",
            str(план["хэш_промпта"]),
            "--ожидаемый-ключ-починки",
            str(план["ключ_починки"]),
            "--идентификатор-попытки",
            попытка,
        ]

    def зарезервировать(
        сам,
        план: dict[str, object],
        поколение: str,
        попытка: str = ПОПЫТКА,
    ) -> subprocess.CompletedProcess[str]:
        return сам.запустить(
            "зарезервировать",
            "--симптом-json",
            json.dumps(СИМПТОМ, ensure_ascii=False),
            *сам.общие_ограждения(план, попытка),
            "--идентификатор-задачи-создателя",
            ЗАДАЧА_СОЗДАТЕЛЯ,
            "--поколение-создателя",
            поколение,
        )

    def подготовить_подтверждённого_исполнителя(
        сам,
    ) -> tuple[dict[str, object], str]:
        допуск_создателя = сам.допустить(ЗАДАЧА_СОЗДАТЕЛЯ)
        план = сам.план()
        поколение_создателя = str(допуск_создателя["generation"])
        резерв = сам.зарезервировать(план, поколение_создателя)
        сам.assertEqual(резерв.returncode, 0, резерв.stderr)
        граница = сам.запустить(
            "начать-вызов-среды",
            *сам.общие_ограждения(план),
            "--идентификатор-задачи-создателя",
            ЗАДАЧА_СОЗДАТЕЛЯ,
            "--поколение-создателя",
            поколение_создателя,
        )
        сам.assertEqual(граница.returncode, 0, граница.stderr)
        завершение_создателя = сам.очередь(
            "finish-clean",
            "--task-id",
            ЗАДАЧА_СОЗДАТЕЛЯ,
            "--generation",
            поколение_создателя,
        )
        сам.assertEqual(завершение_создателя.returncode, 0)
        допуск_исполнителя = сам.допустить(ЗАДАЧА_ИСПОЛНИТЕЛЯ)
        поколение_исполнителя = str(допуск_исполнителя["generation"])
        привязка = сам.запустить(
            "bind-run",
            *сам.общие_ограждения(план),
            "--идентификатор-задачи",
            ЗАДАЧА_ИСПОЛНИТЕЛЯ,
        )
        сам.assertEqual(привязка.returncode, 0, привязка.stderr)
        проверка = сам.запустить(
            "verify-run",
            *сам.общие_ограждения(план),
            "--идентификатор-задачи",
            ЗАДАЧА_ИСПОЛНИТЕЛЯ,
            "--поколение",
            поколение_исполнителя,
        )
        сам.assertEqual(проверка.returncode, 0, проверка.stderr)
        return план, поколение_исполнителя

    def test_план_детерминирован_и_разделяет_публичный_средовой_промпт(
        сам,
    ) -> None:
        первый = сам.план()
        второй = сам.план()

        сам.assertEqual(первый, второй)
        сам.assertEqual(первый["состояние"], "запланирован")
        сам.assertEqual(первый["ветка"], "refs/heads/master")
        сам.assertRegex(str(первый["вершина"]), r"^[0-9a-f]{40,64}$")
        сам.assertRegex(
            str(первый["хэш_промпта"]),
            r"^sha256:[0-9a-f]{64}$",
        )
        сам.assertRegex(
            str(первый["ключ_починки"]),
            r"^sha256:[0-9a-f]{64}$",
        )
        публичный = str(первый["публичный_промпт"])
        полный = str(первый["промпт"])
        сам.assertEqual(
            первый["хэш_промпта"],
            "sha256:" + hashlib.sha256(публичный.encode("utf-8")).hexdigest(),
        )
        сам.assertNotIn(str(сам.репозиторий), публичный)
        сам.assertNotIn(ПОПЫТКА, публичный)
        сам.assertIn("FUM-RUNTIME: не публиковать", полный)
        сам.assertIn(ПОПЫТКА, полный)
        сам.assertIn("первым инструментальным действием", полный)
        сам.assertIn("join", полный)
        сам.assertIn("не запускай ещё одну задачу починки", полный)
        сам.assertIn("только на месте", полный)


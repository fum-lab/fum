    def test_повреждённая_связь_не_подтверждает_коммит(сам) -> None:
        план, поколение_исполнителя = (
            сам.подготовить_подтверждённого_исполнителя()
        )
        (сам.репозиторий / "tracked.txt").write_text(
            "починка завершена\n",
            encoding="utf-8",
        )
        сам.выполнить_команду_системы_версий("add", "tracked.txt")
        коммит = сам.очередь(
            "commit",
            "--task-id",
            ЗАДАЧА_ИСПОЛНИТЕЛЯ,
            "--generation",
            поколение_исполнителя,
            "--message",
            "Исправить автозапуск",
        )
        сам.assertEqual(коммит.returncode, 0, коммит.stderr)
        допуск_наблюдателя = сам.допустить(ЗАДАЧА_СОЗДАТЕЛЯ)
        терминал = сам.запустить(
            "подтвердить-завершение-исполнителя",
            *сам.общие_ограждения(план),
            "--идентификатор-задачи-наблюдателя",
            ЗАДАЧА_СОЗДАТЕЛЯ,
            "--поколение-наблюдателя",
            str(допуск_наблюдателя["generation"]),
        )
        сам.assertEqual(терминал.returncode, 0, терминал.stderr)
        ссылка, исправное = сам.прочитать_состояние_починки()

        без_поколения = json.loads(json.dumps(исправное))
        без_поколения["исполнитель"]["поколение"] = None
        совпавшая_задача = json.loads(json.dumps(исправное))
        совпавшая_задача["исполнитель"]["задача"] = ЗАДАЧА_СОЗДАТЕЛЯ
        совпавшая_задача_иным_регистром = json.loads(json.dumps(исправное))
        совпавшая_задача_иным_регистром["исполнитель"]["задача"] = (
            ЗАДАЧА_СОЗДАТЕЛЯ.upper()
        )
        иная_вершина = json.loads(json.dumps(исправное))
        иная_вершина["исполнитель"]["базовая_вершина"] = "0" * len(
            str(план["вершина"])
        )

        for повреждённое in (
            без_поколения,
            совпавшая_задача,
            совпавшая_задача_иным_регистром,
            иная_вершина,
        ):
            with сам.subTest(исполнитель=повреждённое["исполнитель"]):
                сам.записать_состояние_починки(ссылка, повреждённое)
                результат = сам.запустить("состояние")
                сам.assertEqual(результат.returncode, 2)
                сам.assertFalse(результат.stdout)


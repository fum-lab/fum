"""Повторяемый профиль открытого конечного шаблона, без сети и исходников хоста."""
import argparse
import hashlib
import json
import platform
import statistics
import tempfile
import time
import unicodedata
from pathlib import Path

from test_шаблон_адаптера import модуль, образец, путь_адаптера, путь_скрипта


def измерить(действие, повторы, серии):
    результаты = []
    for _ in range(серии):
        начало = time.perf_counter_ns()
        for _ in range(повторы):
            действие()
        результаты.append(time.perf_counter_ns() - начало)
    return {"повторов_в_серии": повторы, "серий": серии,
            "длительности_серий_наносекунды": результаты,
            "медиана_одного_вызова_наносекунды": statistics.median(результаты) / повторы}


def профиль():
    текст = образец()
    стадии = {}
    for имя in ("исходное_измерение", "повтор_без_изменения_алгоритма"):
        стадии[имя] = {
            "лексика": измерить(lambda: модуль.токены_конечного_адаптера(текст), 1000, 5),
            "полная_проверка_с_лексикой": измерить(lambda: модуль.объявления_адаптера(текст, путь_адаптера), 1000, 5),
            "большой_ввод_с_пробелами": измерить(lambda: модуль.объявления_адаптера(" " * 64000 + текст, путь_адаптера), 10, 5),
        }
    with tempfile.TemporaryDirectory() as временный:
        корень_фикстуры = Path(временный)
        файл_адаптера = корень_фикстуры / путь_адаптера
        файл_адаптера.parent.mkdir(parents=True)
        файл_адаптера.write_text(текст, encoding="utf-8")
        for имя in стадии:
            стадии[имя]["полный_инвентарь_одного_адаптера"] = измерить(
                lambda: модуль.построить_инвентарь(корень_фикстуры), 200, 5)
    корень = Path(__file__).resolve().parents[3]
    файлы = (путь_скрипта, Path(__file__), Path(__file__).with_name("test_шаблон_адаптера.py"))
    return {"схема": "fum.профиль-конечного-адаптера.1",
            "источники": {файл.relative_to(корень).as_posix(): hashlib.sha256(файл.read_bytes()).hexdigest()
                          for файл in файлы},
            "интерпретатор": platform.python_version(), "юникод": unicodedata.unidata_version,
            "вход": текст, "байтов_входа": len(текст.encode()),
            "критерий_обычного_вызова_наносекунды": 1000000,
            "граница": "Монотонные интервалы функций; полная проверка включает лексику, стадии не суммируются. Повтор измеряет ту же реализацию; ускорение не заявляется.",
            "измерения": стадии}


if __name__ == "__main__":
    параметры = argparse.ArgumentParser(description=__doc__)
    параметры.add_argument("--выход", required=True, type=Path)
    аргументы = параметры.parse_args()
    результат = профиль()
    аргументы.выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"измерения": результат["измерения"]}, ensure_ascii=False))

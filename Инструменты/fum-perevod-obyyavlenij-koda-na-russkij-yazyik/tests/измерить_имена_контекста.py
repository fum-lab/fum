#!/usr/bin/env python3
"""Измерить план четырёх исходников и разбор имён на тех же исходных байтах."""

import argparse
import hashlib
import json
from pathlib import Path
import platform
import re
import statistics
import subprocess
import sys
import tempfile
import time

каталог = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(каталог / "scripts"))
import перевести_имена_контекста as миграция


def главная():
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument("--корень", type=Path, required=True)
    разборщик.add_argument("--манифест", type=Path, required=True)
    разборщик.add_argument("--выход", type=Path, required=True)
    разборщик.add_argument("--исходный-коммит")
    параметры = разборщик.parse_args()
    корень = параметры.корень.resolve()
    корень_кода = каталог.parents[1]
    временная_папка = None
    if параметры.исходный_коммит:
        if re.fullmatch(r"[0-9a-f]{40}", параметры.исходный_коммит) is None:
            raise ValueError("нужен полный точный коммит исходных байтов")
        временная_папка = tempfile.TemporaryDirectory(prefix="fum-context-profile-")
        корень_данных = Path(временная_папка.name).resolve()
        for путь in миграция.пути:
            байты = subprocess.check_output(["git", "show", параметры.исходный_коммит + ":" + путь], cwd=корень)
            файл = корень_данных / путь
            файл.parent.mkdir(parents=True, exist_ok=True)
            файл.write_bytes(байты)
        корень = корень_данных
    манифест = миграция.учёт.прочитать_данные(параметры.манифест)
    исходники = {путь: (корень / путь).read_bytes() for путь in sorted(миграция.пути)}
    тексты = {путь: байты.decode("utf-8") for путь, байты in исходники.items()}
    запуски = []
    ожидаемый = None
    for раунд in ("исходный", "повторный"):
        for повтор in range(7):
            запись = {"раунд": раунд, "повтор": повтор + 1}
            начало = time.perf_counter_ns()
            изменения = миграция.подготовить(корень, манифест)
            запись["план_мс"] = (time.perf_counter_ns() - начало) / 1e6
            отпечаток = {и.путь: и.итоговый_хэш for и in изменения}
            if ожидаемый is None:
                ожидаемый = отпечаток
            if ожидаемый != отпечаток:
                raise RuntimeError("неустойчивый результат плана")
            начало = time.perf_counter_ns()
            for текст in тексты.values():
                миграция.учёт.токены_свифт(текст)
            запись["лексика_мс"] = (time.perf_counter_ns() - начало) / 1e6
            начало = time.perf_counter_ns()
            объявления = []
            for путь in исходники:
                объявления.extend(миграция.учёт.объявления_свифт(корень / путь, путь))
            миграция.учёт.отфильтровать_аббревиатуры([о.словарь() for о in объявления])
            запись["объявления_мс"] = (time.perf_counter_ns() - начало) / 1e6
            запуски.append(запись)
    for путь, байты in исходники.items():
        if (корень / путь).read_bytes() != байты:
            raise RuntimeError("профиль изменил исходные байты")
    медианы = {раунд: {стадия: statistics.median(з[стадия] for з in запуски if з["раунд"] == раунд)
                          for стадия in ("план_мс", "лексика_мс", "объявления_мс")}
               for раунд in ("исходный", "повторный")}
    инструменты = [каталог / "scripts/перевести-объявления-кода.py", каталог / "scripts/перевести_имена_контекста.py",
                   каталог / "scripts/аббревиатуры_контекста.py", каталог / "аббревиатуры-контекста.json", Path(__file__)]
    результат = {
        "схема": "fum.профиль-имён-контекста.1",
        "входы": {п: {"байтов": len(б), "хэш": hashlib.sha256(б).hexdigest()} for п, б in исходники.items()},
        "инструменты": {п.relative_to(корень_кода).as_posix(): hashlib.sha256(п.read_bytes()).hexdigest() for п in инструменты},
        "исходный_коммит": параметры.исходный_коммит,
        "среда": {"питон": platform.python_version(), "система": platform.system(), "архитектура": platform.machine()},
        "границы": "Каждая стадия охватывает четыре файла. План включает чтение и проверку хэшей, но исключает применение, импорт и запись отчёта; лексика и разбор перекрывают внутренние стадии плана и не суммируются с ним.",
        "запуски": запуски, "медианы_мс": медианы,
        "критерий": "Медиана полного плана четырёх файлов ниже 1000 мс; одинаковые выходные хэши, исходники не изменяются.",
        "критерий_выполнен": all(м["план_мс"] < 1000 for м in медианы.values()),
        "решение": "Сохранить алгоритм: стоимость ограничена четырьмя файлами, кэш и сложное разрешение связей не оправданы. Повтор без изменения алгоритма не является заявлением об ускорении.",
    }
    параметры.выход.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if временная_папка is not None:
        временная_папка.cleanup()
    return 0 if результат["критерий_выполнен"] else 1


if __name__ == "__main__":
    raise SystemExit(главная())

"""Совместная миграция собственных объявлений, ссылок и шаблона генератора."""

import hashlib
import importlib.util
from pathlib import Path
import sys
import tempfile
import unittest


class ПроверкиМиграцииКонтекста(unittest.TestCase):
    def модуль(сам):
        путь = Path(__file__).resolve().parents[1] / "scripts" / "перевести_имена_контекста.py"
        спецификация = importlib.util.spec_from_file_location("миграция_контекста", путь)
        модуль = importlib.util.module_from_spec(спецификация)
        sys.modules[спецификация.name] = модуль
        спецификация.loader.exec_module(модуль)
        return модуль

    def фикстура(сам, модуль, корень):
        тексты = {
            модуль.путь_контракта: 'struct Поле { let допускаетNull: Bool }\nfunc читать() { let null = "null"; print(null) }\n',
            модуль.путь_поддержки: 'struct КонтрактМоделей { init(base64: String) { print(Data(base64Encoded: base64)) } }\n',
            модуль.путь_генератора: 'let поля = [поле.допускаетNull, поле.допускаетNull, поле.допускаетNull, поле.допускаетNull]\nlet строка = ' + модуль.старый_шаблон + '\n// base64 допускаетNull\n',
            модуль.путь_проверки: 'let результат = КонтрактМоделей(base64: "данные")\n',
        }
        for путь, текст in тексты.items():
            файл = корень / путь
            файл.parent.mkdir(parents=True, exist_ok=True)
            файл.write_text(текст, encoding="utf-8")
        return {"схема": "fum.миграция-имён-контекста.1", "файлы": {
            путь: "sha256:" + hashlib.sha256((корень / путь).read_bytes()).hexdigest() for путь in тексты}}

    def test_объявления_ссылки_и_шаблон_согласованы(сам):
        модуль = сам.модуль()
        with tempfile.TemporaryDirectory() as папка:
            корень = Path(папка).resolve()
            манифест = сам.фикстура(модуль, корень)
            изменения = модуль.подготовить(корень, манифест)
            сам.assertEqual(4, len(изменения))
            сам.assertIn('init(base64:', (корень / модуль.путь_поддержки).read_text())
            модуль.учёт.атомарно_применить(изменения)
            сам.assertIn('Data(base64Encoded: кодированноеОписание)', (корень / модуль.путь_поддержки).read_text())
            сам.assertIn('"null"', (корень / модуль.путь_контракта).read_text())
            сам.assertIn('// base64 допускаетNull', (корень / модуль.путь_генератора).read_text())
            сам.assertIn(модуль.новый_шаблон, (корень / модуль.путь_генератора).read_text())
            сам.assertIn('КонтрактМоделей(кодированноеОписание:', (корень / модуль.путь_проверки).read_text())

    def test_подмена_роли_ссылки_закрывает_весь_план(сам):
        модуль = сам.модуль()
        for подмена in ['чужое.допускаетNull', 'поле.допускаетNull + поле.допускаетNull']:
            with tempfile.TemporaryDirectory() as папка:
                корень = Path(папка).resolve()
                манифест = сам.фикстура(модуль, корень)
                файл = корень / модуль.путь_генератора
                файл.write_text(файл.read_text().replace('поле.допускаетNull', подмена, 1))
                манифест['файлы'][модуль.путь_генератора] = 'sha256:' + hashlib.sha256(файл.read_bytes()).hexdigest()
                with сам.assertRaises(модуль.учёт.ОшибкаКонтракта):
                    модуль.подготовить(корень, манифест)
                сам.assertIn('let допускаетNull', (корень / модуль.путь_контракта).read_text())

    def test_неполный_набор_и_дрейф_не_записываются(сам):
        модуль = сам.модуль()
        with tempfile.TemporaryDirectory() as папка:
            корень = Path(папка).resolve()
            манифест = сам.фикстура(модуль, корень)
            with сам.assertRaises(модуль.учёт.ОшибкаКонтракта):
                модуль.подготовить(корень, {**манифест, 'файлы': {}})
            изменения = модуль.подготовить(корень, манифест)
            файл = корень / модуль.путь_проверки
            файл.write_text(файл.read_text() + '// позднее изменение\n')
            with сам.assertRaises(модуль.учёт.ОшибкаКонтракта):
                модуль.учёт.атомарно_применить(изменения)
            сам.assertIn('let допускаетNull', (корень / модуль.путь_контракта).read_text())


if __name__ == '__main__':
    unittest.main()

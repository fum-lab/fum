def содержит_латиницу(имя: str) -> bool:
    return латиница.search(имя) is not None


def содержит_кириллицу(имя: str) -> bool:
    return кириллица.search(имя) is not None


def разрешённое_внешнее_объявление(имя: str) -> bool:
    if имя.startswith("__") and имя.endswith("__"):
        return True
    if имя in внешние_имена_посетителя:
        return True
    if имя.startswith("test_"):
        остаток = имя[len("test_") :]
        return содержит_кириллицу(остаток) and not содержит_латиницу(остаток)
    return False


def латинское_собственное_имя(имя: str) -> bool:
    return содержит_латиницу(имя) and not разрешённое_внешнее_объявление(имя)


def канонический_текст(значение: object) -> str:
    return json.dumps(
        значение,
        ensure_ascii=False,
        indent=2,
        sort_keys=True,
    ) + "\n"


def вычислить_хэш(данные: bytes) -> str:
    return "sha256:" + hashlib.sha256(данные).hexdigest()


def хэш_файла(файл: Path) -> str:
    return вычислить_хэш(файл.read_bytes())


def путь_исключён(путь: Path) -> bool:
    return any(часть in исключённые_части_пути for часть in путь.parts)


def файлы_репозитория(корень: Path) -> list[Path]:
    найденные: list[Path] = []
    for файл in корень.rglob("*"):
        if путь_исключён(файл.relative_to(корень)):
            continue
        if файл.is_symlink() or not файл.is_file():
            continue
        if файл.suffix.lower() not in {".md", ".py", ".swift"}:
            continue
        найденные.append(файл)
    return sorted(найденные, key=lambda файл: файл.relative_to(корень).as_posix())



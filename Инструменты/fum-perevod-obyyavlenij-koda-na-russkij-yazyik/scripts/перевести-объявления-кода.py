class СборщикОбъявленийПитона(ast.NodeVisitor):
    """Собрать объявления Python из синтаксического дерева."""

    def __init__(сам, путь: str) -> None:
        сам.путь = путь
        сам.объявления: list[Объявление] = []

    def добавить(сам, вид: str, имя: str, узел: ast.AST) -> None:
        добавить_объявление(
            сам.объявления,
            сам.путь,
            "python",
            вид,
            имя,
            getattr(узел, "lineno", 1),
            getattr(узел, "col_offset", 0) + 1,
        )

    def добавить_параметры(сам, параметры: ast.arguments) -> None:
        все_параметры = [
            *параметры.posonlyargs,
            *параметры.args,
            *параметры.kwonlyargs,
        ]
        if параметры.vararg is not None:
            все_параметры.append(параметры.vararg)
        if параметры.kwarg is not None:
            все_параметры.append(параметры.kwarg)
        for параметр in все_параметры:
            сам.добавить("параметр", параметр.arg, параметр)

    def visit_ClassDef(сам, узел: ast.ClassDef) -> None:
        сам.добавить("класс", узел.name, узел)
        сам.generic_visit(узел)

    def visit_FunctionDef(сам, узел: ast.FunctionDef) -> None:
        сам.добавить("функция", узел.name, узел)
        сам.добавить_параметры(узел.args)
        сам.generic_visit(узел)

    def visit_AsyncFunctionDef(сам, узел: ast.AsyncFunctionDef) -> None:
        сам.добавить("функция", узел.name, узел)
        сам.добавить_параметры(узел.args)
        сам.generic_visit(узел)

    def visit_Name(сам, узел: ast.Name) -> None:
        if isinstance(узел.ctx, ast.Store):
            сам.добавить("привязка", узел.id, узел)
        сам.generic_visit(узел)

    def visit_Attribute(сам, узел: ast.Attribute) -> None:
        if isinstance(узел.ctx, ast.Store):
            сам.добавить("атрибут", узел.attr, узел)
        сам.generic_visit(узел)


def объявления_питона(файл: Path, путь: str) -> list[Объявление]:
    текст = файл.read_text(encoding="utf-8")
    дерево = ast.parse(текст, filename=путь)
    сборщик = СборщикОбъявленийПитона(путь)
    сборщик.visit(дерево)
    return сборщик.объявления


def начало_идентификатора_свифт(символ: str) -> bool:
    if символ == "_":
        return True
    категория = unicodedata.category(символ)
    return символ.isalpha() or категория.startswith("L")


def продолжение_идентификатора_свифт(символ: str) -> bool:
    if начало_идентификатора_свифт(символ):
        return True
    категория = unicodedata.category(символ)
    return символ.isdigit() or категория.startswith(("M", "N"))


def токены_свифт(текст: str) -> list[ТокенСвифт]:
    токены: list[ТокенСвифт] = []
    позиция = 0
    строка = 1
    столбец = 1
    длина = len(текст)

    def сдвинуть(число: int) -> None:
        nonlocal позиция, строка, столбец
        фрагмент = текст[позиция : позиция + число]
        переводы = фрагмент.count("\n")
        if переводы:
            строка += переводы
            столбец = len(фрагмент.rsplit("\n", 1)[-1]) + 1
        else:
            столбец += число
        позиция += число

    while позиция < длина:
        символ = текст[позиция]
        if символ.isspace():
            сдвинуть(1)
            continue
        if текст.startswith("//", позиция):
            конец = текст.find("\n", позиция)
            сдвинуть((длина if конец < 0 else конец) - позиция)
            continue
        if текст.startswith("/*", позиция):
            глубина = 1
            начало = позиция
            сдвинуть(2)
            while позиция < длина and глубина:
                if текст.startswith("/*", позиция):
                    глубина += 1
                    сдвинуть(2)
                elif текст.startswith("*/", позиция):
                    глубина -= 1
                    сдвинуть(2)
                else:
                    сдвинуть(1)
            if глубина:
                raise ОшибкаКонтракта(
                    f"незакрытый комментарий Swift со смещения {начало}"
                )
            continue
        if текст.startswith('"""', позиция):
            сдвинуть(3)
            while позиция < длина and not текст.startswith('"""', позиция):
                сдвинуть(1)
            if позиция >= длина:
                raise ОшибкаКонтракта("незакрытая многострочная строка Swift")
            сдвинуть(3)
            continue
        if символ == '"':
            сдвинуть(1)
            экранирован = False
            while позиция < длина:
                текущий = текст[позиция]
                сдвинуть(1)
                if текущий == '"' and not экранирован:
                    break
                if текущий == "\\" and not экранирован:
                    экранирован = True
                else:
                    экранирован = False
            else:
                raise ОшибкаКонтракта("незакрытая строка Swift")
            continue
        if символ == "\x60":
            начальная_строка = строка
            начальный_столбец = столбец
            сдвинуть(1)
            конец = текст.find("\x60", позиция)
            if конец < 0:
                raise ОшибкаКонтракта("незакрытый идентификатор Swift")
            значение = текст[позиция:конец]
            внутреннее_начало = позиция
            сдвинуть(конец - позиция + 1)
            токены.append(
                ТокенСвифт(
                    текст=значение,
                    начало=внутреннее_начало,
                    конец=конец,
                    строка=начальная_строка,
                    столбец=начальный_столбец + 1,
                    вид="идентификатор",
                )
            )
            continue
        if начало_идентификатора_свифт(символ):
            начало = позиция
            начальная_строка = строка
            начальный_столбец = столбец
            сдвинуть(1)
            while позиция < длина and продолжение_идентификатора_свифт(текст[позиция]):
                сдвинуть(1)
            значение = текст[начало:позиция]
            вид = "ключевое_слово" if значение in ключевые_слова_свифт else "идентификатор"
            токены.append(
                ТокенСвифт(
                    текст=значение,
                    начало=начало,
                    конец=позиция,
                    строка=начальная_строка,
                    столбец=начальный_столбец,
                    вид=вид,
                )
            )
            continue
        начало = позиция
        начальная_строка = строка
        начальный_столбец = столбец
        сдвинуть(1)
        токены.append(
            ТокенСвифт(
                текст=символ,
                начало=начало,
                конец=позиция,
                строка=начальная_строка,
                столбец=начальный_столбец,
                вид="знак",
            )
        )
    return токены


def следующий_идентификатор(
    токены: list[ТокенСвифт],
    начало: int,
) -> tuple[int, ТокенСвифт] | None:
    for номер in range(начало, len(токены)):
        токен = токены[номер]
        if токен.вид == "идентификатор":
            return номер, токен
        if токен.текст in {";", "{", "}"}:
            return None
    return None


def параметры_свифт(
    токены: list[ТокенСвифт],
    открывающая: int,
) -> list[ТокенСвифт]:
    параметры: list[ТокенСвифт] = []
    глубина = 0
    начало_части = открывающая + 1
    номер = открывающая + 1
    части: list[tuple[int, int]] = []
    while номер < len(токены):
        текст = токены[номер].текст
        if текст in {"(", "[", "<"}:
            глубина += 1
        elif текст in {")", "]", ">"}:
            if текст == ")" and глубина == 0:
                части.append((начало_части, номер))
                break
            глубина = max(0, глубина - 1)
        elif текст == "," and глубина == 0:
            части.append((начало_части, номер))
            начало_части = номер + 1
        номер += 1
    for начало, конец in части:
        двоеточие = None
        локальная_глубина = 0
        for позиция in range(начало, конец):
            текст = токены[позиция].текст
            if текст in {"(", "[", "<"}:
                локальная_глубина += 1
            elif текст in {")", "]", ">"}:
                локальная_глубина = max(0, локальная_глубина - 1)
            elif текст == ":" and локальная_глубина == 0:
                двоеточие = позиция
                break
        if двоеточие is None:
            continue
        кандидаты = [
            токен
            for токен in токены[начало:двоеточие]
            if токен.вид == "идентификатор"
            and токен.текст not in служебные_слова_параметров_свифт
            and токен.текст != "_"
        ]
        параметры.extend(кандидаты[-2:])
    return параметры


def параметры_замыкания_свифт(
    токены: list[ТокенСвифт],
    открывающая: int,
) -> list[ТокенСвифт]:
    """Найти параметры явной сигнатуры замыкания до слова `in`."""

    начало = открывающая + 1
    глубина = 0
    конец: int | None = None
    for позиция in range(начало, len(токены)):
        текст = токены[позиция].текст
        if текст == "{" and глубина == 0:
            return []
        if текст == "}" and глубина == 0:
            return []
        if текст in {"(", "[", "<"}:
            глубина += 1
        elif текст in {")", "]", ">"}:
            глубина = max(0, глубина - 1)
        elif текст == "in" and глубина == 0:
            конец = позиция
            break
        elif текст == ";" and глубина == 0:
            return []
    if конец is None or конец == начало:
        return []
    сигнатура = токены[начало:конец]
    if сигнатура[0].текст in начала_операторов_свифт:
        return []
    for позиция in range(len(сигнатура) - 1):
        if (
            сигнатура[позиция].текст == "-"
            and сигнатура[позиция + 1].текст == ">"
        ):
            сигнатура = сигнатура[:позиция]
            break
    параметры: list[ТокенСвифт] = []
    двоеточия = [
        позиция
        for позиция, токен in enumerate(сигнатура)
        if токен.текст == ":"
    ]
    if двоеточия:
        for позиция in двоеточия:
            for номер in range(позиция - 1, -1, -1):
                кандидат = сигнатура[номер]
                if кандидат.текст == ",":
                    break
                if кандидат.вид == "идентификатор" and кандидат.текст != "_":
                    параметры.append(кандидат)
                    break
    else:
        параметры.extend(
            токен
            for токен in сигнатура
            if токен.вид == "идентификатор" and токен.текст != "_"
        )
    return параметры


def объявления_свифт(файл: Path, путь: str) -> list[Объявление]:
    текст = файл.read_text(encoding="utf-8")
    токены = токены_свифт(текст)
    объявления: list[Объявление] = []
    for номер, токен in enumerate(токены):
        if токен.текст in ключевые_слова_типов_свифт:
            найденный = следующий_идентификатор(токены, номер + 1)
            if найденный is not None:
                _, имя = найденный
                добавить_объявление(
                    объявления, путь, "swift", "тип",
                    имя.текст, имя.строка, имя.столбец,
                )
        elif токен.текст == "func":
            найденный = следующий_идентификатор(токены, номер + 1)
            if найденный is None:
                continue
            позиция_имени, имя = найденный
            добавить_объявление(
                объявления, путь, "swift", "функция",
                имя.текст, имя.строка, имя.столбец,
            )
            позиция = позиция_имени + 1
            while позиция < len(токены) and токены[позиция].текст != "(":
                if токены[позиция].текст in {"{", ";"}:
                    break
                позиция += 1
            if позиция < len(токены) and токены[позиция].текст == "(":
                for параметр in параметры_свифт(токены, позиция):
                    добавить_объявление(
                        объявления, путь, "swift", "параметр",
                        параметр.текст, параметр.строка, параметр.столбец,
                    )
        elif токен.текст in {"init", "subscript"}:
            позиция = номер + 1
            while позиция < len(токены) and токены[позиция].текст != "(":
                if токены[позиция].текст in {"{", ";"}:
                    break
                позиция += 1
            if позиция < len(токены) and токены[позиция].текст == "(":
                for параметр in параметры_свифт(токены, позиция):
                    добавить_объявление(
                        объявления, путь, "swift", "параметр",
                        параметр.текст, параметр.строка, параметр.столбец,
                    )
        elif токен.текст in {"let", "var"}:
            найденный = следующий_идентификатор(токены, номер + 1)
            if найденный is not None:
                _, имя = найденный
                добавить_объявление(
                    объявления, путь, "swift", "свойство",
                    имя.текст, имя.строка, имя.столбец,
                )
        elif токен.текст == "case":
            позиция = номер + 1
            ожидание_имени = True
            глубина = 0
            while позиция < len(токены):
                кандидат = токены[позиция]
                if кандидат.строка != токен.строка and глубина == 0:
                    break
                if кандидат.текст == "(":
                    глубина += 1
                elif кандидат.текст == ")":
                    глубина = max(0, глубина - 1)
                elif кандидат.текст == "," and глубина == 0:
                    ожидание_имени = True
                elif ожидание_имени and кандидат.вид == "идентификатор":
                    добавить_объявление(
                        объявления, путь, "swift", "вариант",
                        кандидат.текст, кандидат.строка, кандидат.столбец,
                    )
                    ожидание_имени = False
                позиция += 1
        elif токен.текст == "{":
            for параметр in параметры_замыкания_свифт(токены, номер):
                добавить_объявление(
                    объявления, путь, "swift", "параметр",
                    параметр.текст, параметр.строка, параметр.столбец,
                )
    return объявления


def запрос_с_дословным_текстом(путь: str) -> bool:
    части = PurePosixPath(путь).parts
    return len(части) >= 3 and части[0] == "Журнал" and части[-1] == "запрос.md"


def защищённый_раздел(путь: str, раздел: str) -> bool:
    if запрос_с_дословным_текстом(путь) and раздел.startswith("Текст запроса"):
        return True
    if раздел == "Снимок Git":
        return True
    части = PurePosixPath(путь).parts
    return bool(части and части[0] == "Вопросы и ответы" and раздел == "Вопрос")


def диапазоны_мермейд(текст: str, путь: str) -> list[ДиапазонМермейд]:
    диапазоны: list[ДиапазонМермейд] = []
    строки = текст.splitlines(keepends=True)
    смещение = 0
    раздел = ""
    ограда: tuple[str, int, str, int, int, str] | None = None
    for номер_строки, строка in enumerate(строки, start=1):
        без_перевода = строка.rstrip("\r\n")
        if ограда is None:
            заголовок = заголовок_второго_уровня.match(без_перевода)
            if заголовок is not None:
                раздел = заголовок.group(1).strip()
            открытие = открытие_ограды.match(без_перевода)
            if открытие is not None:
                маркер = открытие.group(1)
                описание = открытие.group(2).strip()
                язык = описание.split(maxsplit=1)[0] if описание else ""
                ограда = (
                    маркер[0], len(маркер), язык,
                    смещение + len(строка), номер_строки + 1, раздел,
                )
        else:
            символ, длина, язык, начало, начальная_строка, раздел_ограды = ограда
            закрытие = re.fullmatch(
                rf" {{0,3}}{re.escape(символ)}{{{длина},}}[ \t]*",
                без_перевода,
            )
            if закрытие is not None:
                if язык == "mermaid" and not защищённый_раздел(путь, раздел_ограды):
                    диапазоны.append(
                        ДиапазонМермейд(начало, смещение, начальная_строка)
                    )
                ограда = None
        смещение += len(строка)
    if ограда is not None:
        raise ОшибкаКонтракта(f"{путь}: незакрытая Markdown-ограда")
    return диапазоны


def токены_мермейд(
    текст: str,
    диапазон: ДиапазонМермейд,
) -> list[tuple[str, int, int, int, int]]:
    токены: list[tuple[str, int, int, int, int]] = []
    тело = текст[диапазон.начало : диапазон.конец]
    смещение_строки = диапазон.начало
    закрывающие_скобки: list[str] = []
    for добавка, строка in enumerate(тело.splitlines(keepends=True)):
        позиция = 0
        в_кавычках = False
        экранирован = False
        в_метке_ребра = False
        while позиция < len(строка):
            if not в_кавычках and строка.startswith("%%", позиция):
                break
            символ = строка[позиция]
            if символ == '"' and not экранирован:
                в_кавычках = not в_кавычках
                позиция += 1
                continue
            if в_кавычках:
                if символ == "\\" and not экранирован:
                    экранирован = True
                else:
                    экранирован = False
                позиция += 1
                continue
            if символ == "|":
                в_метке_ребра = not в_метке_ребра
                позиция += 1
                continue
            if в_метке_ребра:
                позиция += 1
                continue
            if символ in {"[", "(", "{"}:
                закрывающие_скобки.append(
                    {"[": "]", "(": ")", "{": "}"}[символ]
                )
                позиция += 1
                continue
            if (
                закрывающие_скобки
                and символ == закрывающие_скобки[-1]
            ):
                закрывающие_скобки.pop()
                позиция += 1
                continue
            if закрывающие_скобки:
                позиция += 1
                continue
            if символ == "_" or символ.isalpha():
                начало = позиция
                позиция += 1
                while позиция < len(строка) and (
                    строка[позиция] == "_" or строка[позиция].isalnum()
                ):
                    позиция += 1
                значение = строка[начало:позиция]
                токены.append(
                    (
                        значение,
                        смещение_строки + начало,
                        смещение_строки + позиция,
                        диапазон.начальная_строка + добавка,
                        начало + 1,
                    )
                )
                continue
            позиция += 1
        смещение_строки += len(строка)
    return токены


def объявления_мермейд(файл: Path, путь: str) -> list[Объявление]:
    текст = файл.read_text(encoding="utf-8")
    объявления: list[Объявление] = []
    for диапазон in диапазоны_мермейд(текст, путь):
        for имя, _, конец, строка, столбец in токены_мермейд(текст, диапазон):
            хвост = текст[конец : диапазон.конец]
            if re.match(r"[ \t]*(\[|\(|\{)", хвост) is None:
                continue
            if имя in служебные_слова_мермейд:
                continue
            добавить_объявление(
                объявления, путь, "mermaid", "узел",
                имя, строка, столбец,
            )
    return объявления


def построить_инвентарь(корень: Path) -> dict[str, object]:
    корень = корень.resolve()
    if not корень.is_dir():
        raise ОшибкаКонтракта("корень репозитория не является каталогом")
    объявления: list[Объявление] = []
    for файл in файлы_репозитория(корень):
        путь = файл.relative_to(корень).as_posix()
        if файл.suffix.lower() == ".py":
            объявления.extend(объявления_питона(файл, путь))
        elif файл.suffix.lower() == ".swift":
            объявления.extend(объявления_свифт(файл, путь))
        else:
            объявления.extend(объявления_мермейд(файл, путь))
    объявления.sort()
    return {
        "версия_схемы": версия_схемы,
        "объявления": [объявление.словарь() for объявление in объявления],
    }


def атомарно_записать(путь: Path, текст: str) -> None:
    путь.parent.mkdir(parents=True, exist_ok=True)
    дескриптор, временное_имя = tempfile.mkstemp(
        prefix=f".{путь.name}.",
        dir=путь.parent,
    )
    временный_путь = Path(временное_имя)
    try:
        with os.fdopen(дескриптор, "w", encoding="utf-8", newline="") as поток:
            поток.write(текст)
            поток.flush()
            os.fsync(поток.fileno())
        os.replace(временный_путь, путь)
    finally:
        if временный_путь.exists():
            временный_путь.unlink()


def прочитать_данные(путь: Path) -> object:
    def собрать_объект(пары: list[tuple[str, object]]) -> dict[str, object]:
        объект: dict[str, object] = {}
        for ключ, значение in пары:
            if ключ in объект:
                raise ОшибкаКонтракта(f"повтор поля JSON: {ключ}")
            объект[ключ] = значение
        return объект

    try:
        return json.loads(
            путь.read_text(encoding="utf-8"),
            object_pairs_hook=собрать_объект,
        )
    except FileNotFoundError as ошибка:
        raise ОшибкаКонтракта(f"JSON-файл не найден: {путь}") from ошибка
    except json.JSONDecodeError as ошибка:
        raise ОшибкаКонтракта(f"неверный JSON в {путь}: {ошибка}") from ошибка


def потребовать_точные_поля(
    значение: dict[str, object],
    ожидаемые: set[str],
    описание: str,
) -> None:
    if set(значение) != ожидаемые:
        raise ОшибкаКонтракта(
            f"{описание}: отсутствуют или добавлены неизвестные поля"
        )


def сводка_снимка(инвентарь: dict[str, object]) -> dict[str, object]:
    объявления = инвентарь["объявления"]
    if not isinstance(объявления, list):
        raise ОшибкаКонтракта("инвентарь не содержит массив объявлений")
    по_языкам: dict[str, int] = {}
    for объявление in объявления:
        if not isinstance(объявление, dict) or not isinstance(
            объявление.get("язык"), str
        ):
            raise ОшибкаКонтракта("инвентарь содержит неверную запись")
        язык = объявление["язык"]
        assert isinstance(язык, str)
        по_языкам[язык] = по_языкам.get(язык, 0) + 1
    return {
        "версия_схемы": версия_схемы,
        "отпечаток_инвентаря": вычислить_хэш(
            канонический_текст(инвентарь).encode("utf-8")
        ),
        "объявлений": len(объявления),
        "по_языкам": dict(sorted(по_языкам.items())),
    }


def проверить_снимок(значение: object) -> dict[str, object]:
    if not isinstance(значение, dict):
        raise ОшибкаКонтракта("корень снимка должен быть JSON-объектом")
    потребовать_точные_поля(
        значение,
        {
            "версия_схемы",
            "объявлений",
            "отпечаток_инвентаря",
            "по_языкам",
        },
        "снимок",
    )
    if значение["версия_схемы"] != версия_схемы:
        raise ОшибкаКонтракта("неподдерживаемая версия схемы снимка")
    отпечаток = значение["отпечаток_инвентаря"]
    if not isinstance(отпечаток, str) or шаблон_хэша.fullmatch(отпечаток) is None:
        raise ОшибкаКонтракта("снимок содержит неверный отпечаток")
    количество = значение["объявлений"]
    if isinstance(количество, bool) or not isinstance(количество, int) or количество < 0:
        raise ОшибкаКонтракта("снимок содержит неверное число объявлений")
    по_языкам = значение["по_языкам"]
    if not isinstance(по_языкам, dict):
        raise ОшибкаКонтракта("сводка языков снимка должна быть объектом")
    if any(
        not isinstance(язык, str)
        or isinstance(число, bool)
        or not isinstance(число, int)
        or число < 0
        for язык, число in по_языкам.items()
    ) or sum(по_языкам.values()) != количество:
        raise ОшибкаКонтракта("снимок содержит неверную сводку языков")
    return значение


def нормализовать_путь(сырой_путь: object) -> str:
    if not isinstance(сырой_путь, str) or not сырой_путь:
        raise ОшибкаКонтракта("путь карты должен быть непустой строкой")
    if "\\" in сырой_путь or "\x00" in сырой_путь:
        raise ОшибкаКонтракта("путь карты должен быть нормализованным POSIX-путём")
    путь = PurePosixPath(сырой_путь)
    if путь.is_absolute() or ".." in путь.parts or путь.as_posix() != сырой_путь:
        raise ОшибкаКонтракта("путь карты должен находиться внутри репозитория")
    if путь.suffix.lower() not in {".md", ".py", ".swift"}:
        raise ОшибкаКонтракта("карта поддерживает только .md, .py и .swift")
    if путь_исключён(Path(*путь.parts)):
        raise ОшибкаКонтракта("карта не может изменять исключённый путь")
    return сырой_путь


def русское_имя(имя: object) -> str:
    if not isinstance(имя, str) or not имя:
        raise ОшибкаКонтракта("новое имя должно быть непустой строкой")
    if not имя.isidentifier() or keyword.iskeyword(имя):
        raise ОшибкаКонтракта(f"новое имя не является идентификатором: {имя}")
    if not содержит_кириллицу(имя):
        raise ОшибкаКонтракта(f"новое имя не содержит кириллицу: {имя}")
    if содержит_латиницу(имя):
        raise ОшибкаКонтракта(f"новое имя содержит латиницу: {имя}")
    return имя


def старое_имя(имя: object) -> str:
    if not isinstance(имя, str) or not имя:
        raise ОшибкаКонтракта("старое имя должно быть непустой строкой")
    if not имя.isidentifier():
        raise ОшибкаКонтракта(f"старое имя не является идентификатором: {имя}")
    if not содержит_латиницу(имя):
        raise ОшибкаКонтракта(f"старое имя не содержит латиницу: {имя}")
    return имя


def прочитать_карту(путь: Path) -> list[ЗаписьКарты]:
    значение = прочитать_данные(путь)
    if not isinstance(значение, dict):
        raise ОшибкаКонтракта("корень карты должен быть JSON-объектом")
    потребовать_точные_поля(значение, {"версия_схемы", "файлы"}, "карта")
    if значение["версия_схемы"] != версия_схемы:
        raise ОшибкаКонтракта("неподдерживаемая версия схемы карты")
    сырые_файлы = значение["файлы"]
    if not isinstance(сырые_файлы, list) or not сырые_файлы:
        raise ОшибкаКонтракта("карта должна содержать непустой массив файлов")
    записи: list[ЗаписьКарты] = []
    встреченные_пути: set[str] = set()
    for номер, сырой_файл in enumerate(сырые_файлы):
        if not isinstance(сырой_файл, dict):
            raise ОшибкаКонтракта(f"файл карты {номер} должен быть объектом")
        потребовать_точные_поля(
            сырой_файл,
            {"путь", "ожидаемый_хэш", "переименования"},
            f"файл карты {номер}",
        )
        путь_файла = нормализовать_путь(сырой_файл["путь"])
        if путь_файла in встреченные_пути:
            raise ОшибкаКонтракта(f"повтор пути карты: {путь_файла}")
        встреченные_пути.add(путь_файла)
        ожидаемый_хэш = сырой_файл["ожидаемый_хэш"]
        if (
            not isinstance(ожидаемый_хэш, str)
            or шаблон_хэша.fullmatch(ожидаемый_хэш) is None
        ):
            raise ОшибкаКонтракта(f"{путь_файла}: неверный хэш")
        сырые_переименования = сырой_файл["переименования"]
        if not isinstance(сырые_переименования, dict) or not сырые_переименования:
            raise ОшибкаКонтракта(
                f"{путь_файла}: переименования должны быть объектом"
            )
        переименования: dict[str, str] = {}
        новые_имена: set[str] = set()
        for сырое_старое, сырое_новое in сырые_переименования.items():
            прежнее = старое_имя(сырое_старое)
            новое = русское_имя(сырое_новое)
            if прежнее == новое:
                raise ОшибкаКонтракта(
                    f"{путь_файла}: старое и новое имя совпадают"
                )
            if новое in новые_имена:
                raise ОшибкаКонтракта(f"{путь_файла}: коллизия новых имён")
            новые_имена.add(новое)
            переименования[прежнее] = новое
        записи.append(
            ЗаписьКарты(путь_файла, ожидаемый_хэш, переименования)
        )
    return sorted(записи, key=lambda запись: запись.путь)


def смещения_строк(текст: str) -> list[int]:
    смещения = [0]
    for совпадение in re.finditer("\n", текст):
        смещения.append(совпадение.end())
    return смещения


def применить_замены(
    текст: str,
    замены: list[tuple[int, int, str, str]],
) -> str:
    результат: list[str] = []
    позиция = 0
    for начало, конец, новое, _ in sorted(замены):
        if начало < позиция:
            raise ОшибкаКонтракта("пересекающиеся токеновые замены")
        результат.append(текст[позиция:начало])
        результат.append(новое)
        позиция = конец
    результат.append(текст[позиция:])
    return "".join(результат)


def замены_питона(
    текст: str,
    переименования: dict[str, str],
) -> tuple[str, dict[str, int], set[str]]:
    смещения = смещения_строк(текст)
    замены: list[tuple[int, int, str, str]] = []
    имена: set[str] = set()
    for токен in tokenize.generate_tokens(io.StringIO(текст).readline):
        if токен.type != tokenize.NAME:
            continue
        имена.add(токен.string)
        if токен.string not in переименования:
            continue
        начало = смещения[токен.start[0] - 1] + токен.start[1]
        конец = смещения[токен.end[0] - 1] + токен.end[1]
        замены.append(
            (начало, конец, переименования[токен.string], токен.string)
        )
    количества = {
        прежнее: sum(
            1 for _, _, _, исходное in замены if исходное == прежнее
        )
        for прежнее in переименования
    }
    return применить_замены(текст, замены), количества, имена


def замены_свифт(
    текст: str,
    переименования: dict[str, str],
) -> tuple[str, dict[str, int], set[str]]:
    токены = токены_свифт(текст)
    имена = {
        токен.текст for токен in токены if токен.вид == "идентификатор"
    }
    замены = [
        (токен.начало, токен.конец, переименования[токен.текст], токен.текст)
        for токен in токены
        if токен.вид == "идентификатор"
        and токен.текст in переименования
    ]
    количества = {
        прежнее: sum(
            1 for _, _, _, исходное in замены if исходное == прежнее
        )
        for прежнее in переименования
    }
    return применить_замены(текст, замены), количества, имена


def замены_мермейд(
    текст: str,
    путь: str,
    переименования: dict[str, str],
) -> tuple[str, dict[str, int], set[str]]:
    замены: list[tuple[int, int, str, str]] = []
    имена: set[str] = set()
    for диапазон in диапазоны_мермейд(текст, путь):
        for имя, начало, конец, _, _ in токены_мермейд(текст, диапазон):
            имена.add(имя)
            if имя in переименования:
                замены.append((начало, конец, переименования[имя], имя))
    количества = {
        прежнее: sum(
            1 for _, _, _, исходное in замены if исходное == прежнее
        )
        for прежнее in переименования
    }
    return применить_замены(текст, замены), количества, имена


def объявления_одного_файла(файл: Path, путь: str) -> list[Объявление]:
    if файл.suffix.lower() == ".py":
        return объявления_питона(файл, путь)
    if файл.suffix.lower() == ".swift":
        return объявления_свифт(файл, путь)
    if файл.suffix.lower() == ".md":
        return объявления_мермейд(файл, путь)
    raise ОшибкаКонтракта(f"{путь}: неподдерживаемый тип файла")


def подготовить_изменения(
    корень: Path,
    записи: list[ЗаписьКарты],
) -> list[ИзменениеФайла]:
    корень = корень.resolve()
    изменения: list[ИзменениеФайла] = []
    for запись in записи:
        указанный_файл = корень
        for часть in PurePosixPath(запись.путь).parts:
            указанный_файл /= часть
            if указанный_файл.is_symlink():
                raise ОшибкаКонтракта(
                    f"{запись.путь}: путь содержит символическую ссылку"
                )
        файл = указанный_файл.resolve()
        try:
            файл.relative_to(корень)
        except ValueError as ошибка:
            raise ОшибкаКонтракта(
                f"{запись.путь}: путь вышел из репозитория"
            ) from ошибка
        if not файл.is_file():
            raise ОшибкаКонтракта(
                f"{запись.путь}: файл отсутствует или является ссылкой"
            )
        исходные_байты = файл.read_bytes()
        наблюдаемый_хэш = вычислить_хэш(исходные_байты)
        if наблюдаемый_хэш != запись.ожидаемый_хэш:
            raise ОшибкаКонтракта(f"{запись.путь}: неверный хэш")
        исходный_текст = исходные_байты.decode("utf-8")
        объявленные_имена = {
            объявление.имя
            for объявление in объявления_одного_файла(файл, запись.путь)
        }
        отсутствующие = set(запись.переименования) - объявленные_имена
        if отсутствующие:
            перечисление = ", ".join(sorted(отсутствующие))
            raise ОшибкаКонтракта(
                f"{запись.путь}: старые имена не являются объявлениями: "
                f"{перечисление}"
            )
        if файл.suffix.lower() == ".py":
            новый_текст, количества, все_имена = замены_питона(
                исходный_текст, запись.переименования
            )
        elif файл.suffix.lower() == ".swift":
            новый_текст, количества, все_имена = замены_свифт(
                исходный_текст, запись.переименования
            )
        else:
            новый_текст, количества, все_имена = замены_мермейд(
                исходный_текст, запись.путь, запись.переименования
            )
        старые = set(запись.переименования)
        for прежнее, новое in запись.переименования.items():
            if новое in все_имена and новое not in старые:
                raise ОшибкаКонтракта(
                    f"{запись.путь}: коллизия имени {прежнее} с {новое}"
                )
            if количества[прежнее] < 1:
                raise ОшибкаКонтракта(
                    f"{запись.путь}: имя {прежнее} не встретилось в токенах"
                )
        изменения.append(
            ИзменениеФайла(
                путь=запись.путь,
                файл=файл,
                новый_текст=новый_текст,
                исходный_хэш=наблюдаемый_хэш,
                итоговый_хэш=вычислить_хэш(новый_текст.encode("utf-8")),
                переименования=запись.переименования,
                количества=количества,
            )
        )
    return изменения


def описание_плана(
    изменения: list[ИзменениеФайла],
    режим: str,
) -> dict[str, object]:
    return {
        "версия_схемы": версия_схемы,
        "режим": режим,
        "файлы": [
            {
                "путь": изменение.путь,
                "исходный_хэш": изменение.исходный_хэш,
                "итоговый_хэш": изменение.итоговый_хэш,
                "замены": [
                    {
                        "старое_имя": прежнее,
                        "новое_имя": изменение.переименования[прежнее],
                        "количество": изменение.количества[прежнее],
                    }
                    for прежнее in sorted(изменение.количества)
                ],
            }
            for изменение in изменения
        ],
    }


def атомарно_применить(изменения: list[ИзменениеФайла]) -> None:
    временные: list[tuple[ИзменениеФайла, Path]] = []
    try:
        for изменение in изменения:
            дескриптор, имя = tempfile.mkstemp(
                prefix=f".{изменение.файл.name}.",
                dir=изменение.файл.parent,
            )
            временный = Path(имя)
            режим = stat.S_IMODE(изменение.файл.stat().st_mode)
            with os.fdopen(
                дескриптор, "w", encoding="utf-8", newline=""
            ) as поток:
                поток.write(изменение.новый_текст)
                поток.flush()
                os.fsync(поток.fileno())
            os.chmod(временный, режим)
            временные.append((изменение, временный))
        for изменение, _ in временные:
            if хэш_файла(изменение.файл) != изменение.исходный_хэш:
                raise ОшибкаКонтракта(
                    f"{изменение.путь}: хэш изменился после построения плана"
                )
        for изменение, временный in временные:
            os.replace(временный, изменение.файл)
    finally:
        for _, временный in временные:
            if временный.exists():
                временный.unlink()


def добавить_общие_аргументы(разборщик: argparse.ArgumentParser) -> None:
    разборщик.add_argument(
        "--корень-репозитория",
        required=True,
        help="Корень проверяемого checkout.",
    )


def построить_разборщик() -> argparse.ArgumentParser:
    разборщик = argparse.ArgumentParser(
        description="Перевод собственных объявлений кода FUM на русский язык."
    )
    команды = разборщик.add_subparsers(dest="команда", required=True)
    инвентаризация = команды.add_parser("инвентаризировать")
    добавить_общие_аргументы(инвентаризация)
    обновление = команды.add_parser("обновить-снимок")
    добавить_общие_аргументы(обновление)
    обновление.add_argument("--снимок", required=True)
    проверка = команды.add_parser("проверить")
    добавить_общие_аргументы(проверка)
    проверка.add_argument("--снимок", required=True)
    план = команды.add_parser("план")
    добавить_общие_аргументы(план)
    план.add_argument("--карта", required=True)
    применение = команды.add_parser("применить")
    добавить_общие_аргументы(применение)
    применение.add_argument("--карта", required=True)
    return разборщик


def выполнить(аргументы: argparse.Namespace) -> int:
    корень = Path(аргументы.корень_репозитория)
    if аргументы.команда == "инвентаризировать":
        sys.stdout.write(канонический_текст(построить_инвентарь(корень)))
        return 0
    if аргументы.команда == "обновить-снимок":
        снимок = сводка_снимка(построить_инвентарь(корень))
        атомарно_записать(Path(аргументы.снимок), канонический_текст(снимок))
        sys.stdout.write(
            канонический_текст(
                {
                    "версия_схемы": версия_схемы,
                    "состояние": "снимок_обновлён",
                    "путь": str(Path(аргументы.снимок)),
                }
            )
        )
        return 0
    if аргументы.команда == "проверить":
        ожидаемый = проверить_снимок(прочитать_данные(Path(аргументы.снимок)))
        наблюдаемый = сводка_снимка(построить_инвентарь(корень))
        if ожидаемый != наблюдаемый:
            raise ОшибкаКонтракта("снимок не совпадает с текущим остатком")
        sys.stdout.write(
            канонический_текст(
                {
                    "версия_схемы": версия_схемы,
                    "состояние": "снимок_совпадает",
                    "объявлений": наблюдаемый["объявлений"],
                }
            )
        )
        return 0
    записи = прочитать_карту(Path(аргументы.карта))
    изменения = подготовить_изменения(корень, записи)
    if аргументы.команда == "план":
        sys.stdout.write(канонический_текст(описание_плана(изменения, "план")))
        return 0
    if аргументы.команда == "применить":
        атомарно_применить(изменения)
        sys.stdout.write(
            канонический_текст(описание_плана(изменения, "применено"))
        )
        return 0
    raise ОшибкаКонтракта("неизвестная команда")


def главная() -> int:
    разборщик = построить_разборщик()
    аргументы = разборщик.parse_args()
    try:
        return выполнить(аргументы)
    except (
        ОшибкаКонтракта,
        OSError,
        UnicodeDecodeError,
        SyntaxError,
        tokenize.TokenError,
    ) as ошибка:
        print(f"ошибка: {ошибка}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(главная())

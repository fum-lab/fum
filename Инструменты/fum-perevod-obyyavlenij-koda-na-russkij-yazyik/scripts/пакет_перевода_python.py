"""Подготовить хэшированный пакет собственных привязок и явных потребителей.

Связь владельца с поставщиком задаёт проверенная человеком карта; AST проверяет
конечные места употреблений и количества, но не выводит типы объектов.
"""
from __future__ import annotations

import argparse
import ast
from collections import Counter
import hashlib
import importlib.util
import json
from pathlib import Path, PurePosixPath
import re
import sys
import time

from безопасные_привязки_python import подготовить_замены, ОтказПеревода


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def точный_файл(корень, имя):
    if not isinstance(имя, str) or not имя or '\\' in имя or PurePosixPath(имя).is_absolute():
        raise ОтказПеревода('Неканонический путь пакета')
    части = имя.split('/')
    if any(ч in {'', '.', '..'} for ч in части) or not имя.endswith('.py'):
        raise ОтказПеревода('Неканонический путь Python')
    путь = корень
    for часть in части:
        if not путь.is_dir() or часть not in {п.name for п in путь.iterdir()}:
            raise ОтказПеревода(f'{имя}: отсутствующий путь или неверный регистр')
        путь /= часть
        if путь.is_symlink():
            raise ОтказПеревода(f'{имя}: символическая ссылка')
    if not путь.is_file():
        raise ОтказПеревода(f'{имя}: не обычный файл')
    return путь


def проверить_переводы(карта):
    if not isinstance(карта, dict):
        raise ОтказПеревода('Карта должна быть объектом')
    for старое, новое in карта.items():
        if not isinstance(старое, str) or not isinstance(новое, str) or not старое.isidentifier() or not новое.isidentifier():
            raise ОтказПеревода('Недопустимое имя')
        if not re.search('[А-Яа-яЁё]', новое) or старое == новое:
            raise ОтказПеревода('Требуется новое русское имя')
    if len(set(карта.values())) != len(карта):
        raise ОтказПеревода('Несколько прежних имён имеют один результат')


def применить_диапазоны(текст, правки):
    части, позиция = [], 0
    for правка in sorted(правки, key=lambda п: п['начало']):
        от, до = правка['начало'], правка['конец']
        if от < позиция or текст[от:до] != правка['старое']:
            raise ОтказПеревода('Пересечение или неверный диапазон связи')
        части.extend((текст[позиция:от], правка['новое']))
        позиция = до
    return ''.join([*части, текст[позиция:]])


def подготовить_связи(текст, связи, записи, код=None):
    дерево = ast.parse(текст)
    строки = текст.splitlines(keepends=True)
    смещения = [0]
    for строка in строки:
        смещения.append(смещения[-1] + len(строка))

    def позиция(строка, столбец):
        return смещения[строка - 1] + len(строки[строка - 1].encode()[:столбец].decode())

    правки = []
    for встроенный in код or []:
        if set(встроенный) != {'строка', 'столбец', 'хэш', 'переводы'}:
            raise ОтказПеревода('Неизвестные поля встроенного кода')
        проверить_переводы(встроенный['переводы'])
        найденные = [у for у in ast.walk(дерево) if isinstance(у, ast.Constant) and isinstance(у.value, str)
                     and (у.lineno, у.col_offset) == (встроенный['строка'], встроенный['столбец'])]
        if len(найденные) != 1 or хэш(найденные[0].value.encode()) != встроенный['хэш']:
            raise ОтказПеревода('Не совпал точный встроенный исходник')
        узел = найденные[0]
        итог, внутренние, _ = подготовить_замены(узел.value, встроенный['переводы'])
        if set(встроенный['переводы']) - {п['старое'] for п in внутренние}:
            raise ОтказПеревода('Встроенная карта содержит отсутствующее имя')
        от, до = позиция(узел.lineno, узел.col_offset), позиция(узел.end_lineno, узел.end_col_offset)
        правки.append({'начало': от, 'конец': до, 'старое': текст[от:до], 'новое': repr(итог),
                       'роль': 'встроенный_код', 'привязки': внутренние})
    for связь in связи:
        if set(связь) != {'вид', 'владелец', 'имя', 'новое', 'количество', 'источник'}:
            raise ОтказПеревода('Неизвестные поля связи')
        источник = записи.get(связь['источник'])
        if источник is None or источник['переводы'].get(связь['имя']) != связь['новое']:
            raise ОтказПеревода('Связь не подтверждена картой поставщика')
        if type(связь['количество']) is not int or связь['количество'] < 1:
            raise ОтказПеревода('Неверное количество связей')
        найденные = []
        for узел in ast.walk(дерево):
            if связь['вид'] == 'атрибут':
                if not isinstance(узел, ast.Attribute) or узел.attr != связь['имя'] or ast.unparse(узел.value) != связь['владелец']:
                    continue
                до = позиция(узел.end_lineno, узел.end_col_offset)
                найденные.append({'начало': до - len(узел.attr), 'конец': до, 'старое': узел.attr, 'новое': связь['новое']})
            elif связь['вид'] == 'строковый_атрибут':
                if not isinstance(узел, ast.Call) or not isinstance(узел.func, ast.Attribute) or узел.func.attr != 'object' or len(узел.args) < 2:
                    continue
                строковый = узел.args[1]
                if ast.unparse(узел.args[0]) != связь['владелец'] or not isinstance(строковый, ast.Constant) or строковый.value != связь['имя']:
                    continue
                от = позиция(строковый.lineno, строковый.col_offset)
                до = позиция(строковый.end_lineno, строковый.end_col_offset)
                фрагмент = текст[от:до]
                if фрагмент not in {repr(связь['имя']), json.dumps(связь['имя'], ensure_ascii=False)}:
                    raise ОтказПеревода('Строковая связь требует простого строкового токена')
                найденные.append({'начало': от + 1, 'конец': до - 1, 'старое': связь['имя'], 'новое': связь['новое']})
            else:
                raise ОтказПеревода('Неизвестный вид связи')
        if len(найденные) != связь['количество']:
            raise ОтказПеревода(f"Связь {связь['владелец']}.{связь['имя']}: ожидалось {связь['количество']}, найдено {len(найденные)}")
        правки.extend({**п, 'роль': связь['вид'], 'источник': связь['источник']} for п in найденные)
    return применить_диапазоны(текст, правки), правки


def перенести_координату(текст, координата, правки):
    строка, столбец = координата
    if (строка, столбец) == (0, 0):
        return (0, 0)
    строки = текст.splitlines(keepends=True)
    if type(строка) is not int or type(столбец) is not int or not 1 <= строка <= len(строки) or столбец < 0:
        raise ОтказПеревода('Неверная координата')
    начало = sum(map(len, строки[:строка - 1]))
    позиция = начало + len(строки[строка - 1].encode()[:столбец].decode())
    поправка = 0
    for правка in правки:
        if начало <= правка['начало'] < позиция:
            if правка['конец'] > позиция or '\n' in правка['новое']:
                raise ОтказПеревода('Связь пересекает координату области')
            поправка += len(правка['новое'].encode()) - len(правка['старое'].encode())
    return строка, столбец + поправка


def подготовить(корень, манифест, измерения=None):
    начало = time.perf_counter_ns()
    корень = Path(корень).resolve(strict=True)
    if set(манифест) != {'схема', 'файлы'} or манифест['схема'] != 'fum.пакет-перевода-python.1' or not isinstance(манифест['файлы'], list):
        raise ОтказПеревода('Неизвестная схема пакета')
    записи, исходники = {}, {}
    for запись in манифест['файлы']:
        обязательные = {'путь', 'хэш', 'переводы', 'области', 'связи', 'передачи'}
        if not обязательные <= set(запись) or set(запись) - обязательные - {'имена_областей', 'код', 'исполнения', 'внешние_вызовы'}:
            raise ОтказПеревода('Неизвестные поля файла')
        имя = запись['путь']
        if имя in записи:
            raise ОтказПеревода('Повторный путь')
        путь = точный_файл(корень, имя)
        байты = путь.read_bytes()
        if хэш(байты) != запись['хэш']:
            raise ОтказПеревода(f'{имя}: неверный хэш входа')
        проверить_переводы(запись['переводы'])
        записи[имя], исходники[имя] = запись, байты.decode('utf-8')
    изменения = []
    for имя, запись in записи.items():
        отметка = time.perf_counter_ns()
        текст = исходники[имя]
        связанный, связи = подготовить_связи(текст, запись['связи'], записи, запись.get('код'))
        выбор = None
        if запись['области'] is not None:
            if set(запись['области']) - запись['переводы'].keys():
                raise ОтказПеревода('Выбор области не принадлежит карте')
            from безопасные_привязки_python import ОбластиПитона
            области = ОбластиПитона(ast.parse(связанный))
            выбор = {(getattr(о.узел, 'lineno', 0), getattr(о.узел, 'col_offset', 0), и)
                     for о in области.области for и in о.привязки
                     if и in запись['переводы'] and и not in запись['области']}
            for старое, координаты in запись['области'].items():
                выбор.update((*перенести_координату(текст, к, связи), старое) for к in координаты)
        передачи = {(*перенести_координату(текст, п[:2], связи), п[2]) for п in запись['передачи']}
        исполнения = {перенести_координату(текст, п, связи) for п in запись.get('исполнения', [])}
        внешние_вызовы = {перенести_координату(текст, п, связи) for п in запись.get('внешние_вызовы', [])}
        имена_областей = {}
        for строка, столбец, старое, новое in запись.get('имена_областей', []):
            проверить_переводы({старое: новое})
            ключ = (*перенести_координату(текст, [строка, столбец], связи), старое)
            if ключ in имена_областей:
                raise ОтказПеревода('Повторная область отдельного имени')
            имена_областей[ключ] = новое
        try:
            итог, привязки, _ = подготовить_замены(связанный, запись['переводы'], выбор, разрешённые_передачи=передачи, имена_областей=имена_областей, разрешённые_исполнения=исполнения, разрешённые_внешние_вызовы=внешние_вызовы)
        except ValueError as ошибка:
            raise ОтказПеревода(f'{имя}: {ошибка}') from ошибка
        отсутствующие = set(запись['переводы']) - {п['старое'] for п in привязки}
        if отсутствующие:
            raise ОтказПеревода(f'{имя}: отсутствующие собственные привязки: {sorted(отсутствующие)}')
        изменения.append({'путь': имя, 'файл': корень / имя, 'корень': корень, 'до': запись['хэш'], 'после': хэш(итог.encode()),
                          'текст': итог, 'переводы': запись['переводы'], 'связи': связи, 'привязки': привязки})
        if измерения is not None:
            измерения.append({'стадия': имя, 'длительность_наносекунды': time.perf_counter_ns() - отметка})
    if измерения is not None:
        измерения.append({'стадия': 'весь_пакет', 'длительность_наносекунды': time.perf_counter_ns() - начало})
    return изменения


def описание(план):
    return {'схема': 'fum.план-перевода-python.1', 'файлы': [{к: з[к] for к in ('путь', 'до', 'после', 'переводы', 'связи', 'привязки')} for з in план]}


def применить(план):
    for запись in план:
        файл = точный_файл(запись['корень'], запись['путь'])
        if файл != запись['файл'] or хэш(файл.read_bytes()) != запись['до'] or хэш(запись['текст'].encode()) != запись['после']:
            raise ОтказПеревода('Пакет изменился после построения плана')
    спецификация = importlib.util.spec_from_file_location('исполнитель_пакета_питона', Path(__file__).with_name('перевести-объявления-кода.py'))
    модуль = importlib.util.module_from_spec(спецификация)
    sys.modules[спецификация.name] = модуль
    спецификация.loader.exec_module(модуль)
    изменения = [модуль.ИзменениеФайла(з['путь'], з['файл'], з['текст'], 'sha256:' + з['до'], 'sha256:' + з['после'], з['переводы'], dict(Counter(п['старое'] for п in з['привязки']))) for з in план]
    модуль.атомарно_применить(изменения)


def без_повторов(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ОтказПеревода('Повторный ключ JSON')
        результат[ключ] = значение
    return результат


def выполнить():
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument('команда', choices=['план', 'применить'])
    разборщик.add_argument('--корень-репозитория', required=True)
    разборщик.add_argument('--карта', required=True)
    разборщик.add_argument('--выход', required=True)
    аргументы = разборщик.parse_args()
    манифест = json.loads(Path(аргументы.карта).read_text(), object_pairs_hook=без_повторов)
    план = подготовить(Path(аргументы.корень_репозитория), манифест)
    данные = json.dumps(описание(план), ensure_ascii=False, indent=2) + '\n'
    Path(аргументы.выход).write_text(данные)
    if аргументы.команда == 'применить':
        применить(план)
    print(f"{аргументы.команда}: файлов {len(план)}, хэш плана {хэш(данные.encode())}")


if __name__ == '__main__':
    выполнить()

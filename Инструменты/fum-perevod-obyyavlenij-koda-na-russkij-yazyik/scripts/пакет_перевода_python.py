from безопасные_привязки_python import подготовить_замены, ОтказПеревода, ОбластиПитона, ПроисхождениеПитона


def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def точный_файл(корень, имя):
    if not isinstance(имя, str) or not имя or '\\' in имя or PurePosixPath(имя).is_absolute():
        raise ОтказПеревода('Неканонический путь пакета')
    части = имя.split('/')
    if any(ч in {'', '.', '..'} for ч in части) or not имя.endswith('.py'):
        raise ОтказПеревода('Неканонический путь Python')
    путь = корень
    for часть in части:
        if not путь.is_dir() or часть not in {п.name for п in путь.iterdir()}:
            raise ОтказПеревода(f'{имя}: отсутствующий путь или неверный регистр')
        путь /= часть
        if путь.is_symlink():
            raise ОтказПеревода(f'{имя}: символическая ссылка')
    if not путь.is_file():
        raise ОтказПеревода(f'{имя}: не обычный файл')
    return путь


def проверить_переводы(карта):
    if not isinstance(карта, dict):
        raise ОтказПеревода('Карта должна быть объектом')
    for старое, новое in карта.items():
        if not isinstance(старое, str) or not isinstance(новое, str) or not старое.isidentifier() or not новое.isidentifier():
            raise ОтказПеревода('Недопустимое имя')
        if not re.search('[А-Яа-яЁё]', новое) or старое == новое:
            raise ОтказПеревода('Требуется новое русское имя')
    if len(set(карта.values())) != len(карта):
        raise ОтказПеревода('Несколько прежних имён имеют один результат')


def применить_диапазоны(текст, правки):
    части, позиция = [], 0
    for правка in sorted(правки, key=lambda п: п['начало']):
        от, до = правка['начало'], правка['конец']
        if от < позиция or текст[от:до] != правка['старое']:
            raise ОтказПеревода('Пересечение или неверный диапазон связи')
        части.extend((текст[позиция:от], правка['новое']))
        позиция = до
    return ''.join([*части, текст[позиция:]])


def связи_импорта(дерево, связь, смещения, строки):
    """Закрепить имя поставщика и употребления единственной импортной привязки."""
    compile(дерево, '<связь импорта>', 'exec', dont_inherit=True)
    области = ОбластиПитона(дерево)
    старое, новое = связь['имя'], связь['новое']
    if not isinstance(связь['владелец'], str) or not связь['владелец']:
        raise ОтказПеревода('Импорт требует точного имени модуля')
    найденные = []

    def диапазон(узел, имя):
        от = смещения[узел.lineno - 1] + len(строки[узел.lineno - 1].encode()[:узел.col_offset].decode())
        return {'начало': от, 'конец': от + len(имя), 'старое': имя, 'новое': новое}

    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.ImportFrom) or узел.module != связь['владелец'] or узел.level != 0:
            continue
        if any(п.name == '*' for п in узел.names):
            raise ОтказПеревода('Неограниченный импорт требует отдельного допуска')
        for псевдоним in узел.names:
            if псевдоним.name != старое:
                continue
            местное = псевдоним.asname or старое
            владелец = области.владельцы[псевдоним].владелец(местное)
            if владелец is None or владелец.привязки[местное] != [('псевдоним' if псевдоним.asname else 'внешнее', псевдоним)]:
                raise ОтказПеревода('Неоднозначная импортная привязка')
            найденные.append(диапазон(псевдоним, старое))
            if псевдоним.asname:
                continue
            if any(новое in о.привязки for о in области.области):
                raise ОтказПеревода('Новое имя импорта перехватывается другой привязкой')
            for употребление in ast.walk(дерево):
                if isinstance(употребление, (ast.Global, ast.Nonlocal)) and старое in употребление.names:
                    raise ОтказПеревода('Связь импорта с global/nonlocal требует отдельного допуска')
                if isinstance(употребление, ast.Call):
                    имя_вызова = употребление.func.id if isinstance(употребление.func, ast.Name) else getattr(употребление.func, 'attr', '')
                    if имя_вызова in {'globals', 'locals', 'eval', 'exec'}:
                        raise ОтказПеревода('Динамическое пространство импортного имени требует отдельного допуска')
                    if имя_вызова in {'getattr', 'setattr', 'delattr', 'hasattr', 'object'} and any(isinstance(а, ast.Constant) and а.value == старое for а in употребление.args):
                        raise ОтказПеревода('Строковый потребитель импорта требует отдельного допуска')
                if isinstance(употребление, (ast.Assign, ast.AnnAssign)):
                    цели = употребление.targets if isinstance(употребление, ast.Assign) else [употребление.target]
                    if any(isinstance(ц, ast.Name) and ц.id == '__all__' for ц in цели) and any(isinstance(а, ast.Constant) and а.value == старое for а in ast.walk(употребление)):
                        raise ОтказПеревода('Строковый экспорт импорта требует отдельного допуска')
                if isinstance(употребление, ast.Name) and употребление.id == старое and isinstance(употребление.ctx, ast.Load) and области.владельцы[употребление].владелец(старое) is владелец:
                    найденные.append(диапазон(употребление, старое))
    return найденные


def подготовить_связи(текст, связи, записи, код=None, поля=None):
    дерево = ast.parse(текст)
    строки = текст.splitlines(keepends=True)
    смещения = [0]
    for строка in строки:
        смещения.append(смещения[-1] + len(строка))

    def позиция(строка, столбец):
        return смещения[строка - 1] + len(строки[строка - 1].encode()[:столбец].decode())

    правки = list(поля or ())
    for встроенный in код or []:
        if set(встроенный) != {'строка', 'столбец', 'хэш', 'переводы'}:
            raise ОтказПеревода('Неизвестные поля встроенного кода')
        проверить_переводы(встроенный['переводы'])
        найденные = [у for у in ast.walk(дерево) if isinstance(у, ast.Constant) and isinstance(у.value, str)
                     and (у.lineno, у.col_offset) == (встроенный['строка'], встроенный['столбец'])]
        if len(найденные) != 1 or хэш(найденные[0].value.encode()) != встроенный['хэш']:
            raise ОтказПеревода('Не совпал точный встроенный исходник')
        узел = найденные[0]
        итог, внутренние, _ = подготовить_замены(узел.value, встроенный['переводы'])
        if set(встроенный['переводы']) - {п['старое'] for п in внутренние}:
            raise ОтказПеревода('Встроенная карта содержит отсутствующее имя')
        от, до = позиция(узел.lineno, узел.col_offset), позиция(узел.end_lineno, узел.end_col_offset)
        правки.append({'начало': от, 'конец': до, 'старое': текст[от:до], 'новое': repr(итог),
                       'роль': 'встроенный_код', 'привязки': внутренние})
    for связь in связи:
        if set(связь) != {'вид', 'владелец', 'имя', 'новое', 'количество', 'источник'}:
            raise ОтказПеревода('Неизвестные поля связи')
        источник = записи.get(связь['источник'])
        if источник is None or источник['переводы'].get(связь['имя']) != связь['новое']:
            raise ОтказПеревода('Связь не подтверждена картой поставщика')
        if type(связь['количество']) is not int or связь['количество'] < 1:
            raise ОтказПеревода('Неверное количество связей')
        найденные = связи_импорта(дерево, связь, смещения, строки) if связь['вид'] == 'импорт' else []
        for узел in ([] if связь['вид'] == 'импорт' else ast.walk(дерево)):
            if связь['вид'] == 'атрибут':
                if not isinstance(узел, ast.Attribute) or узел.attr != связь['имя'] or ast.unparse(узел.value) != связь['владелец']:
                    continue
                до = позиция(узел.end_lineno, узел.end_col_offset)
                найденные.append({'начало': до - len(узел.attr), 'конец': до, 'старое': узел.attr, 'новое': связь['новое']})
            elif связь['вид'] == 'строковый_атрибут':
                if not isinstance(узел, ast.Call) or not isinstance(узел.func, ast.Attribute) or узел.func.attr != 'object' or len(узел.args) < 2:
                    continue
                строковый = узел.args[1]
                if ast.unparse(узел.args[0]) != связь['владелец'] or not isinstance(строковый, ast.Constant) or строковый.value != связь['имя']:
                    continue
                от = позиция(строковый.lineno, строковый.col_offset)
                до = позиция(строковый.end_lineno, строковый.end_col_offset)
                фрагмент = текст[от:до]
                if фрагмент not in {repr(связь['имя']), json.dumps(связь['имя'], ensure_ascii=False)}:
                    raise ОтказПеревода('Строковая связь требует простого строкового токена')
                найденные.append({'начало': от + 1, 'конец': до - 1, 'старое': связь['имя'], 'новое': связь['новое']})
            else:
                raise ОтказПеревода('Неизвестный вид связи')
        if len(найденные) != связь['количество']:
            raise ОтказПеревода(f"Связь {связь['владелец']}.{связь['имя']}: ожидалось {связь['количество']}, найдено {len(найденные)}")
        правки.extend({**п, 'роль': связь['вид'], 'источник': связь['источник']} for п in найденные)
    return применить_диапазоны(текст, правки), правки


def подготовить_поля_модулей(поля, записи, исходники):
    """Доказать конечную группу над исходными AST до первой замены.

    Координаты — строки с единицы и байтовые столбцы с нуля. SHA задаются
    записями файлов. Одинаковое написание владельца не является связью.
    """
    if not isinstance(поля, list):
        raise ОтказПеревода('Поля модулей должны быть списком')
    анализ = {путь: ПроисхождениеПитона(ast.parse(текст)) for путь, текст in исходники.items()}
    правки = {путь: [] for путь in записи}
    учтённые = {путь: set() for путь in записи}
    имена, новые_имена = set(), set()
    for поле in поля:
        if not isinstance(поле, dict) or set(поле) != {'имя', 'новое', 'источник', 'владельцы', 'употребления', 'количество'}:
            raise ОтказПеревода('Неизвестные поля контракта модуля')
        старое, новое, источник = поле['имя'], поле['новое'], поле['источник']
        проверить_переводы({старое: новое})
        if (re.search('[A-Za-z]', новое) or any(и != unicodedata.normalize('NFKC', и) for и in (старое, новое))
                or any(и.startswith('__') for и in (старое, новое)) or новое in новые_имена
                or старое in имена or источник not in записи or записи[источник]['переводы'].get(старое) != новое):
            raise ОтказПеревода('Поле не подтверждено единственной картой поставщика')
        имена.add(старое)
        новые_имена.add(новое)
        if (type(поле['количество']) is not int or поле['количество'] < 1
                or not isinstance(поле['владельцы'], list) or not поле['владельцы']
                or not isinstance(поле['употребления'], list) or len(поле['употребления']) != поле['количество']):
            raise ОтказПеревода('Неверный полный счёт поля модуля')
        владельцы = []
        for владелец in поле['владельцы']:
            if not isinstance(владелец, dict) or set(владелец) != {'путь', 'имя', 'область', 'получение'}:
                raise ОтказПеревода('Неизвестные поля владельца')
            путь = владелец['путь']
            if путь not in анализ or not isinstance(владелец['имя'], str):
                raise ОтказПеревода('Нет закреплённого исходника владельца')
            for координата in ('область', 'получение'):
                значение = владелец[координата]
                if not isinstance(значение, list) or len(значение) != 2 or any(type(ч) is not int or ч < 0 for ч in значение):
                    raise ОтказПеревода('Некорректная координата владельца')
            найденные = [о for о in анализ[путь].области.области
                if [getattr(о.узел, 'lineno', 0), getattr(о.узел, 'col_offset', 0)] == владелец['область']]
            if len(найденные) != 1:
                raise ОтказПеревода('Не найдена единственная область владельца')
            область = найденные[0]
            привязки = область.привязки.get(владелец['имя'], [])
            if len(привязки) != 1 or [привязки[0][1].lineno, привязки[0][1].col_offset] != владелец['получение']:
                raise ОтказПеревода('Перепривязанный или неизвестный владелец модуля')
            ключ = (путь, область, владелец['имя'])
            if ключ in владельцы:
                raise ОтказПеревода('Повторный владелец модуля')
            владельцы.append(ключ)
        ожидаемые = set()
        for употребление in поле['употребления']:
            if not isinstance(употребление, dict) or set(употребление) != {'путь', 'строка', 'столбец', 'вид', 'владелец'}:
                raise ОтказПеревода('Неизвестные поля потребителя')
            if (употребление['путь'] not in записи or type(употребление['строка']) is not int or употребление['строка'] < 1
                    or type(употребление['столбец']) is not int or употребление['столбец'] < 0
                    or type(употребление['владелец']) is not int or not 0 <= употребление['владелец'] < len(владельцы)
                    or употребление['вид'] not in {'запись', 'чтение', 'getattr', 'patch.object'}):
                raise ОтказПеревода('Некорректный потребитель модуля')
            ключ = tuple(употребление[к] for к in ('путь', 'строка', 'столбец', 'вид', 'владелец'))
            if ключ in ожидаемые:
                raise ОтказПеревода('Повторный потребитель модуля')
            ожидаемые.add(ключ)
        найденные, использованы, записи_поля = set(), set(), 0
        for путь, происхождение in анализ.items():
            текст = исходники[путь]
            строки = текст.splitlines(keepends=True)
            смещения = [0]
            for строка in строки:
                смещения.append(смещения[-1] + len(строка))

            def позиция(узел, конец=False):
                номер = узел.end_lineno if конец else узел.lineno
                столбец = узел.end_col_offset if конец else узел.col_offset
                return смещения[номер - 1] + len(строки[номер - 1].encode()[:столбец].decode())

            for узел in ast.walk(происхождение.дерево):
                вид, получатель, токен = None, None, None
                if isinstance(узел, ast.Attribute) and узел.attr == старое:
                    if not isinstance(узел.ctx, (ast.Store, ast.Load)):
                        raise ОтказПеревода('Удаление поля модуля не поддержано')
                    вид = 'запись' if isinstance(узел.ctx, ast.Store) else 'чтение'
                    получатель = узел.value
                    до = позиция(узел, True)
                    токен = (до - len(старое), до)
                elif isinstance(узел, ast.Call) and len(узел.args) >= 2:
                    имя_интерфейса = узел.func.id if isinstance(узел.func, ast.Name) else getattr(узел.func, 'attr', '')
                    строка = узел.args[1]
                    строковое = isinstance(строка, ast.Constant) and строка.value == старое
                    связан = isinstance(узел.args[0], ast.Name) and any(
                            п == путь and и == узел.args[0].id and происхождение.области.владельцы[узел.args[0]].владелец(и) is о
                            for п, о, и in владельцы)
                    if (связан or имя_интерфейса in {'getattr', 'setattr', 'delattr', 'hasattr', 'object'}
                            or происхождение.встроенное(узел.func, 'getattr')):
                        if not isinstance(строка, ast.Constant):
                            raise ОтказПеревода('Вычисляемое имя поля модуля')
                        if связан and строка.value in {'__dict__', '__dir__', '__getattribute__', '__getattr__', '__setattr__', '__delattr__', '__class__'}:
                            raise ОтказПеревода('Строковый доступ к рефлексии модуля')
                        if связан and строка.value == новое:
                            raise ОтказПеревода('Коллизия строкового имени поля модуля')
                        if строковое:
                            if происхождение.встроенное(узел.func, 'getattr'):
                                вид = 'getattr'
                            elif происхождение.путь_внешнего_интерфейса(узел.func) == ('unittest', 'mock', 'patch', 'object'):
                                вид = 'patch.object'
                            else:
                                raise ОтказПеревода('Не доказан неизменённый API строкового потребителя')
                            получатель = узел.args[0]
                            от, до = позиция(строка), позиция(строка, True)
                            if текст[от:до] not in {repr(старое), json.dumps(старое, ensure_ascii=False)}:
                                raise ОтказПеревода('Поле требует простой строковый токен')
                            токен = (от + 1, до - 1)
                if вид is None:
                    continue
                if not isinstance(получатель, ast.Name) or not происхождение.модуль(получатель):
                    raise ОтказПеревода('Не доказано происхождение владельца поля')
                область = происхождение.области.владельцы[получатель].владелец(получатель.id)
                ключ_владельца = (путь, область, получатель.id)
                if ключ_владельца not in владельцы:
                    raise ОтказПеревода('Потребитель вне закреплённого владельца')
                номер = владельцы.index(ключ_владельца)
                ключ = (путь, узел.lineno, узел.col_offset, вид, номер)
                найденные.add(ключ)
                использованы.add(номер)
                записи_поля += вид == 'запись' and путь == источник
                if any(isinstance(ч, ast.Name) and unicodedata.normalize('NFC', ч.id) == unicodedata.normalize('NFC', новое)
                       or isinstance(ч, ast.Attribute) and unicodedata.normalize('NFC', ч.attr) == unicodedata.normalize('NFC', новое)
                       for ч in ast.walk(происхождение.дерево)) or any(
                           unicodedata.normalize('NFC', и) == unicodedata.normalize('NFC', новое)
                           for о in происхождение.области.области for и in о.привязки):
                    raise ОтказПеревода('Коллизия нового поля модуля')
                правки[путь].append({'начало': токен[0], 'конец': токен[1], 'старое': старое,
                    'новое': новое, 'роль': 'поле_модуля_' + вид, 'источник': источник})
            родители = {ч: у for у in ast.walk(происхождение.дерево) for ч in ast.iter_child_nodes(у)}
            for узел in ast.walk(происхождение.дерево):
                if not isinstance(узел, ast.Name) or not isinstance(узел.ctx, ast.Load):
                    continue
                область = происхождение.области.владельцы[узел].владелец(узел.id)
                if (путь, область, узел.id) not in владельцы:
                    continue
                родитель = родители.get(узел)
                if isinstance(родитель, ast.Attribute) and родитель.value is узел:
                    if родитель.attr in {'__dir__', '__getattribute__', '__getattr__', '__setattr__', '__delattr__', '__class__'}:
                        raise ОтказПеревода('Неподдержанная рефлексия владельца модуля')
                    if родитель.attr == '__dict__':
                        вызов = родители.get(родитель)
                        if not (isinstance(вызов, ast.Call) and происхождение.встроенное(вызов.func, 'exec')
                                and родитель in вызов.args[1:]
                                and [вызов.lineno, вызов.col_offset] in записи[путь].get('исполнения', [])):
                            raise ОтказПеревода('Незакреплённое динамическое пространство модуля')
                    continue
                if isinstance(родитель, ast.Call) and узел in родитель.args:
                    разрешён = (родитель.args[0] is узел and
                        (происхождение.встроенное(родитель.func, 'getattr')
                         or происхождение.путь_внешнего_интерфейса(родитель.func) == ('unittest', 'mock', 'patch', 'object')))
                    if not разрешён:
                        raise ОтказПеревода('Непроверенная передача владельца поля модуля')
                    continue
                raise ОтказПеревода('Непроверенный потребитель или контейнер владельца модуля')
        if найденные != ожидаемые or использованы != set(range(len(владельцы))) or not записи_поля:
            raise ОтказПеревода('Неполная связь собственного поля модуля')
        учтённые[источник].add(старое)
    return правки, учтённые


def перенести_координату(текст, координата, правки):
    строка, столбец = координата
    if (строка, столбец) == (0, 0):
        return (0, 0)
    строки = текст.splitlines(keepends=True)
    if type(строка) is not int or type(столбец) is not int or not 1 <= строка <= len(строки) or столбец < 0:
        raise ОтказПеревода('Неверная координата')
    начало = sum(map(len, строки[:строка - 1]))
    позиция = начало + len(строки[строка - 1].encode()[:столбец].decode())
    поправка = 0
    for правка in правки:
        if начало <= правка['начало'] < позиция:
            if правка['конец'] > позиция or '\n' in правка['новое']:
                raise ОтказПеревода('Связь пересекает координату области')
            поправка += len(правка['новое'].encode()) - len(правка['старое'].encode())
    return строка, столбец + поправка


def подготовить(корень, манифест, измерения=None):
    начало = time.perf_counter_ns()
    корень = Path(корень).resolve(strict=True)
    вторая = манифест.get('схема') == 'fum.пакет-перевода-python.2'
    if (set(манифест) != ({'схема', 'файлы', 'поля_модулей'} if вторая else {'схема', 'файлы'})
            or манифест['схема'] not in {'fum.пакет-перевода-python.1', 'fum.пакет-перевода-python.2'} or not isinstance(манифест['файлы'], list)):
        raise ОтказПеревода('Неизвестная схема пакета')
    записи, исходники = {}, {}
    for запись in манифест['файлы']:
        обязательные = {'путь', 'хэш', 'переводы', 'области', 'связи', 'передачи'}
        if not обязательные <= set(запись) or set(запись) - обязательные - {'имена_областей', 'код', 'исполнения', 'внешние_вызовы'}:
            raise ОтказПеревода('Неизвестные поля файла')
        имя = запись['путь']
        if имя in записи:
            raise ОтказПеревода('Повторный путь')
        путь = точный_файл(корень, имя)
        байты = путь.read_bytes()
        if хэш(байты) != запись['хэш']:
            raise ОтказПеревода(f'{имя}: неверный хэш входа')
        проверить_переводы(запись['переводы'])
        записи[имя], исходники[имя] = запись, байты.decode('utf-8')
    отметка_полей = time.perf_counter_ns()
    поля, учтённые = подготовить_поля_модулей(манифест['поля_модулей'], записи, исходники) if вторая else ({}, {})
    if вторая and измерения is not None:
        измерения.append({'стадия': 'доказательство_полей', 'длительность_наносекунды': time.perf_counter_ns() - отметка_полей})
    изменения = []
    for имя, запись in записи.items():
        отметка = time.perf_counter_ns()
        текст = исходники[имя]
        связанный, связи = подготовить_связи(текст, запись['связи'], записи, запись.get('код'), поля.get(имя))
        связанные_атрибуты = []
        сдвиг = 0
        for связь in sorted(связи, key=lambda правка: правка['начало']):
            if связь['роль'] in {'атрибут', 'поле_модуля_запись', 'поле_модуля_чтение'}:
                начало_диапазона = связь['начало'] + сдвиг
                связанные_атрибуты.append((начало_диапазона, начало_диапазона + len(связь['новое'])))
            сдвиг += len(связь['новое']) - (связь['конец'] - связь['начало'])
        выбор = None
        if запись['области'] is not None:
            if set(запись['области']) - запись['переводы'].keys():
                raise ОтказПеревода('Выбор области не принадлежит карте')
            from безопасные_привязки_python import ОбластиПитона
            области = ОбластиПитона(ast.parse(связанный))
            выбор = {(getattr(о.узел, 'lineno', 0), getattr(о.узел, 'col_offset', 0), и)
                     for о in области.области for и in о.привязки
                     if и in запись['переводы'] and и not in запись['области']}
            for старое, координаты in запись['области'].items():
                выбор.update((*перенести_координату(текст, к, связи), старое) for к in координаты)
        передачи = {(*перенести_координату(текст, п[:2], связи), п[2]) for п in запись['передачи']}
        исполнения = {перенести_координату(текст, п, связи) for п in запись.get('исполнения', [])}
        внешние_вызовы = {перенести_координату(текст, п, связи) for п in запись.get('внешние_вызовы', [])}
        имена_областей = {}
        for строка, столбец, старое, новое in запись.get('имена_областей', []):
            проверить_переводы({старое: новое})
            ключ = (*перенести_координату(текст, [строка, столбец], связи), старое)
            if ключ in имена_областей:
                raise ОтказПеревода('Повторная область отдельного имени')
            имена_областей[ключ] = новое
        try:
            итог, привязки, _ = подготовить_замены(связанный, запись['переводы'], выбор, разрешённые_передачи=передачи, имена_областей=имена_областей, разрешённые_исполнения=исполнения, разрешённые_внешние_вызовы=внешние_вызовы, связанные_атрибуты=связанные_атрибуты)
        except ValueError as ошибка:
            raise ОтказПеревода(f'{имя}: {ошибка}') from ошибка
        отсутствующие = set(запись['переводы']) - {п['старое'] for п in привязки} - учтённые.get(имя, set())
        if отсутствующие:
            raise ОтказПеревода(f'{имя}: отсутствующие собственные привязки: {sorted(отсутствующие)}')
        изменения.append({'путь': имя, 'файл': корень / имя, 'корень': корень, 'до': запись['хэш'], 'после': хэш(итог.encode()),
                          'текст': итог, 'переводы': запись['переводы'], 'связи': связи, 'привязки': привязки})
        if вторая:
            изменения[-1]['контракт_полей'] = манифест['поля_модулей']
        if измерения is not None:
            измерения.append({'стадия': имя, 'длительность_наносекунды': time.perf_counter_ns() - отметка})
    if измерения is not None:
        измерения.append({'стадия': 'весь_пакет', 'длительность_наносекунды': time.perf_counter_ns() - начало})
    return изменения


def описание(план):
    вторая = bool(план and 'контракт_полей' in план[0])
    результат = {'схема': 'fum.план-перевода-python.2' if вторая else 'fum.план-перевода-python.1',
        'файлы': [{к: з[к] for к in ('путь', 'до', 'после', 'переводы', 'связи', 'привязки')} for з in план]}
    if вторая:
        результат['поля_модулей'] = план[0]['контракт_полей']
    return результат


def применить(план):
    for запись in план:
        файл = точный_файл(запись['корень'], запись['путь'])
        if файл != запись['файл'] or хэш(файл.read_bytes()) != запись['до'] or хэш(запись['текст'].encode()) != запись['после']:
            raise ОтказПеревода('Пакет изменился после построения плана')
    # Только новый формат допускает проверенный явный повтор без замены inode.
    изменяемые = [з for з in план if 'контракт_полей' not in з or з['до'] != з['после']]
    if not изменяемые:
        return
    спецификация = importlib.util.spec_from_file_location('исполнитель_пакета_питона', Path(__file__).with_name('перевести-объявления-кода.py'))
    модуль = importlib.util.module_from_spec(спецификация)
    sys.modules[спецификация.name] = модуль
    спецификация.loader.exec_module(модуль)
    изменения = [модуль.ИзменениеФайла(з['путь'], з['файл'], з['текст'], 'sha256:' + з['до'], 'sha256:' + з['после'], з['переводы'], dict(Counter(п['старое'] for п in з['привязки']))) for з in изменяемые]
    модуль.атомарно_применить(изменения)


def без_повторов(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ОтказПеревода('Повторный ключ JSON')
        результат[ключ] = значение
    return результат


def выполнить():
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument('команда', choices=['план', 'применить'])
    разборщик.add_argument('--корень-репозитория', required=True)
    разборщик.add_argument('--карта', required=True)
    разборщик.add_argument('--выход', required=True)
    аргументы = разборщик.parse_args()
    манифест = json.loads(Path(аргументы.карта).read_text(), object_pairs_hook=без_повторов)
    план = подготовить(Path(аргументы.корень_репозитория), манифест)
    данные = json.dumps(описание(план), ensure_ascii=False, indent=2) + '\n'
    Path(аргументы.выход).write_text(данные)
    if аргументы.команда == 'применить':
        применить(план)
    print(f"{аргументы.команда}: файлов {len(план)}, хэш плана {хэш(данные.encode())}")


if __name__ == '__main__':
    выполнить()

"""Подготовить хэшированный пакет собственных привязок и явных потребителей.

Связь владельца с поставщиком задаёт проверенная человеком карта; AST проверяет
конечные места употреблений и количества, но не выводит типы объектов.
"""
from __future__ import annotations

import argparse
import ast
from collections import Counter
import hashlib
import importlib.util
import json
from pathlib import Path, PurePosixPath
import re
import sys
import time

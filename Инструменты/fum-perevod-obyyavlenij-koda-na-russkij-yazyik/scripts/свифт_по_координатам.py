def защищённые_области(текст):
    """Строки целиком, включая интерполяции, и вложенные комментарии неизменяемы."""
    области = []
    def строка(начало):
        разделитель = '"""' if текст.startswith('"""', начало) else '"'
        позиция = начало + len(разделитель)
        while позиция < len(текст):
            if текст.startswith('\\(', позиция):
                позиция = интерполяция(позиция + 2)
            elif текст[позиция] == '\\': позиция += 2
            elif текст.startswith(разделитель, позиция): return позиция + len(разделитель)
            else: позиция += 1
        raise ValueError('Незакрытая строка Swift')
    def комментарий(начало):
        позиция = начало + 2; глубина = 1
        while позиция < len(текст):
            if текст.startswith('/*', позиция): глубина += 1; позиция += 2
            elif текст.startswith('*/', позиция):
                глубина -= 1; позиция += 2
                if not глубина: return позиция
            else: позиция += 1
        raise ValueError('Незакрытый комментарий Swift')
    def интерполяция(позиция):
        глубина = 1
        while позиция < len(текст):
            if текст[позиция] == '"': позиция = строка(позиция)
            elif текст.startswith('/*', позиция): позиция = комментарий(позиция)
            elif текст.startswith('//', позиция):
                конец = текст.find('\n', позиция); позиция = len(текст) if конец < 0 else конец
            elif текст[позиция] == '(' : глубина += 1; позиция += 1
            elif текст[позиция] == ')':
                глубина -= 1; позиция += 1
                if not глубина: return позиция
            else: позиция += 1
        raise ValueError('Незакрытая интерполяция Swift')
    позиция = 0
    while позиция < len(текст):
        if текст.startswith(('#"', '#/'), позиция): raise ValueError('Расширенный строковый литерал вне ограниченного адаптера')
        начало = позиция
        if текст.startswith('//', позиция):
            конец = текст.find('\n', позиция); позиция = len(текст) if конец < 0 else конец
        elif текст.startswith('/*', позиция): позиция = комментарий(позиция)
        elif текст[позиция] == '"': позиция = строка(позиция)
        else: позиция += 1; continue
        области.append((начало, позиция))
    return области


def прочитать_область(корень, область):
    текущий = корень
    for часть in Path(область).parts:
        if часть not in os.listdir(текущий) or (текущий / часть).is_symlink():
            raise ValueError('Область отсутствует, отличается регистром или содержит ссылку')
        текущий /= часть
    результат = {}
    def ошибка_обхода(ошибка): raise ошибка
    for каталог, подпапки, файлы in os.walk(текущий, followlinks=False, onerror=ошибка_обхода):
        подпапки[:] = sorted(имя for имя in подпапки if имя not in ('.build', '.swiftpm', '.git'))
        for имя in подпапки + файлы:
            путь = Path(каталог) / имя
            if путь.is_symlink(): raise ValueError('В проектном инвентаре есть символическая ссылка')
        for имя in sorted(файлы):
            if Path(имя).suffix.lower() != '.swift': continue
            путь = Path(каталог) / имя
            if путь.suffix != '.swift' or not путь.is_file(): raise ValueError('Неверный тип исходника Swift')
            результат[путь.relative_to(корень).as_posix()] = путь.read_bytes()
    return результат


def маска_кода(текст):
    маска = list(текст)
    for начало, конец in защищённые_области(текст):
        маска[начало:конец] = ['\n' if символ == '\n' else ' ' for символ in текст[начало:конец]]
    return ''.join(маска)


def сохранить_контракт(путь, текст, контракты, символы):
    прежние = [текст[начало:конец] for начало, конец in защищённые_области(текст)]
    добавленные = []; выполнены = []
    маска = маска_кода(текст)
    if 'сохранить-ключ-формата' in контракты and путь.endswith('/Sources/ЯдроМашины/ПодготовкаUbuntu.swift'):
        новое = символы.get('format')
        if новое != 'форматОбраза': raise ValueError('Не задано ожидаемое имя поля формата')
        образец = 'enum CodingKeys: String, CodingKey { case ' + новое + ','
        if маска.count(образец) != 1: raise ValueError('Исходный ключ формата отсутствует, уже закреплён или неоднозначен')
        конец = маска.index(образец) + len(образец) - 1
        текст = текст[:конец] + ' = "format"' + текст[конец:]
        добавленные.append('"format"'); выполнены.append('сохранить-ключ-формата')
    if 'сохранить-ключи-запуска' in контракты and путь.endswith('/Sources/ЯдроМашины/Управление.swift'):
        if символы.get('портSSH') != 'портДоступаКГостю': raise ValueError('Не задано ожидаемое имя порта')
        заголовок = 'public struct ЗапускМашины: Codable {'
        if маска.count(заголовок) != 1: raise ValueError('Нет единственного типа запуска')
        начало = маска.index(заголовок) + len(заголовок)
        конец = маска.find('\n    public init(', начало)
        if конец < 0 or 'CodingKeys' in маска[начало:]: raise ValueError('Ключи уже заданы или нарушено строение типа запуска')
        поля = ['схема', 'машина', 'план', 'запуск', 'токен', 'портДоступаКГостю', 'портУправления', 'фаза', 'причина']
        if re.findall(r'\bvar\s+(\w+)', маска[начало:конец]) != поля:
            raise ValueError('Набор полей запуска изменился; автоматическая миграция остановлена')
        ключи = '\n    enum CodingKeys: String, CodingKey {\n' + ''.join(
            '        case ' + поле + ' = "' + ('портSSH' if поле == 'портДоступаКГостю' else поле) + '"\n' for поле in поля) + '    }\n'
        текст = текст[:конец] + ключи + текст[конец:]
        добавленные += ['"' + ('портSSH' if поле == 'портДоступаКГостю' else поле) + '"' for поле in поля]
        выполнены.append('сохранить-ключи-запуска')
    нынешние = [текст[начало:конец] for начало, конец in защищённые_области(текст)]
    if Counter(нынешние) != Counter(прежние + добавленные): raise ValueError('Операция кодирования изменила защищённые байты')
    позиция = 0
    for область in нынешние:
        if позиция < len(прежние) and прежние[позиция] == область: позиция += 1
    if позиция != len(прежние): raise ValueError('Операция кодирования переставила защищённые области')
    return текст, выполнены


def подготовить(корень, карта, канон):
    канон.потребовать_точные_поля(карта, {'версия_схемы', 'адаптер', 'область', 'файлы', 'символы', 'вхождения', 'контракты'}, 'карта координат')
    if type(карта['версия_схемы']) is not int or карта['версия_схемы'] != 2 or карта['адаптер'] != 'свифт-координаты.1':
        raise ValueError('Неизвестный координатный адаптер')
    область = карта['область']
    if область != 'Проекты/ВиртуальнаяМашина': raise ValueError('Адаптер ограничен проектом виртуальной машины')
    контракты = карта['контракты']
    допустимые = {'сохранить-ключ-формата': 'Sources/ЯдроМашины/ПодготовкаUbuntu.swift',
                  'сохранить-ключи-запуска': 'Sources/ЯдроМашины/Управление.swift'}
    if (not isinstance(контракты, list) or any(тип not in допустимые for тип in контракты)
            or len(set(контракты)) != len(контракты)): raise ValueError('Неизвестная или повторная операция кодирования')
    корень = корень.resolve()
    входы = прочитать_область(корень, область)
    if any(область + '/' + допустимые[тип] not in входы for тип in контракты): raise ValueError('Нет исходника закрепляемого контракта')
    хэши = {}
    if not isinstance(карта['файлы'], list) or not карта['файлы']: raise ValueError('Нет закреплённых исходников')
    for запись in карта['файлы']:
        канон.потребовать_точные_поля(запись, {'путь', 'ожидаемый_хэш'}, 'исходник координат')
        путь = канон.нормализовать_путь(запись['путь'])
        if путь in хэши: raise ValueError('Повтор исходника')
        хэши[путь] = запись['ожидаемый_хэш']
    if хэши != {путь: канон.вычислить_хэш(байты) for путь, байты in входы.items()}:
        raise ValueError('Изменились набор или хэши Swift-файлов проекта')
    символы = карта['символы']
    if not isinstance(символы, dict) or not символы: raise ValueError('Нет выбранных символов')
    for прежнее, новое in символы.items(): канон.старое_имя(прежнее); канон.русское_имя(новое)
    if len(set(символы.values())) != len(символы): raise ValueError('Коллизия русских имён')
    кандидаты = {}; тексты = {}; защищено = {}; кодовые = set(); новые_в_коде = set()
    шаблон = re.compile(r'(?<!\w)(?:' + '|'.join(re.escape(имя) for имя in sorted(символы, key=len, reverse=True)) + r')(?!\w)')
    for путь, байты in входы.items():
        текст = байты.decode('utf-8'); тексты[путь] = текст
        области = защищённые_области(текст); маска = list(текст)
        защищено[путь] = [канон.вычислить_хэш(текст[начало:конец].encode()) for начало, конец in области]
        for начало, конец in области:
            маска[начало:конец] = ['\n' if символ == '\n' else ' ' for символ in текст[начало:конец]]
        for токен in канон.токены_свифт(''.join(маска)):
            if токен.вид == 'идентификатор':
                новые_в_коде.add(токен.текст)
                кодовые.add((путь, len(текст[:токен.начало].encode()), len(текст[:токен.конец].encode())))
        for совпадение in шаблон.finditer(текст):
            ключ = (путь, len(текст[:совпадение.start()].encode()), len(текст[:совпадение.end()].encode()))
            кандидаты[ключ] = совпадение.group()
    if set(символы.values()) & новые_в_коде: raise ValueError('Коллизия с существующим именем проекта')
    замены = {путь: [] for путь in входы}; классифицированы = set(); объявлены = set()
    if not isinstance(карта['вхождения'], list): raise ValueError('Нет классификации вхождений')
    for запись in карта['вхождения']:
        канон.потребовать_точные_поля(запись, {'путь', 'начало', 'конец', 'имя', 'роль', 'основание'}, 'вхождение')
        if any(type(запись[поле]) is not int for поле in ('начало', 'конец')): raise ValueError('Неверный тип координаты')
        ключ = (запись['путь'], запись['начало'], запись['конец'])
        if ключ in классифицированы or кандидаты.get(ключ) != запись['имя']: raise ValueError('Нет целого токена по координатам или он повторён')
        классифицированы.add(ключ)
        if not isinstance(запись['основание'], str) or not запись['основание'].strip(): raise ValueError('Нет основания классификации')
        роль = запись['роль']; код = ключ in кодовые
        if роль == 'буквальное':
            if код: raise ValueError('Код нельзя объявить буквальным текстом')
        elif роль in ('внешнее', 'служебное'):
            if not код: raise ValueError('Защищённый текст требует буквальной роли')
        elif роль in ('объявление', 'употребление'):
            if not код: raise ValueError('Изменение строки, комментария или интерполяции запрещено')
            if роль == 'объявление': объявлены.add(запись['имя'])
            замены[запись['путь']].append((запись['начало'], запись['конец'], символы[запись['имя']].encode(), запись['имя']))
        else: raise ValueError('Неизвестная роль вхождения')
    if классифицированы != set(кандидаты) or объявлены != set(символы): raise ValueError('Неполное покрытие вхождений или объявлений')
    for имя, контракт in [('format', 'сохранить-ключ-формата'), ('портSSH', 'сохранить-ключи-запуска')]:
        if any(старое == имя for _, _, _, старое in замены.get(область + '/' + допустимые[контракт], [])) and контракт not in контракты:
            raise ValueError('Переименование требует сохранения внешнего ключа: ' + имя)
    изменения = []; исполненные_контракты = []
    for путь, замены_файла in замены.items():
        if not замены_файла: continue
        байты = входы[путь]; итог = bytearray(); позиция = 0
        for начало, конец, новое, _ in sorted(замены_файла):
            итог.extend(байты[позиция:начало]); итог.extend(новое); позиция = конец
        итог.extend(байты[позиция:]); текст = итог.decode('utf-8')
        if защищено[путь] != [канон.вычислить_хэш(текст[начало:конец].encode()) for начало, конец in защищённые_области(текст)]:
            raise ValueError('Защищённые байты изменились')
        текст, выполнены = сохранить_контракт(путь, текст, контракты, символы)
        исполненные_контракты.extend(выполнены)
        пары = {имя: символы[имя] for _, _, _, имя in замены_файла}
        количества = {имя: sum(старое == имя for _, _, _, старое in замены_файла) for имя in пары}
        изменения.append(канон.ИзменениеФайла(путь, корень / путь, текст, хэши[путь], канон.вычислить_хэш(текст.encode()), пары, количества))
    if sorted(исполненные_контракты) != sorted(контракты): raise ValueError('Заявленная операция кодирования не выполнена ровно один раз')
    план = канон.описание_плана(изменения, 'план')
    план.update(версия_схемы=2, адаптер='свифт-координаты.1', защищённые_области=защищено, классификация=карта['вхождения'], контракты=контракты)
    отпечаток = канон.вычислить_хэш(канон.канонический_текст({'карта': карта, 'план': план,
        'адаптер': канон.вычислить_хэш(Path(__file__).read_bytes()), 'канон': канон.вычислить_хэш(Path(канон.__file__).read_bytes())}).encode())
    план['отпечаток_плана'] = отпечаток
    def проверить_входы():
        if входы != прочитать_область(корень, область): raise ValueError('Входы изменились после построения плана')
    return изменения, план, проверить_входы

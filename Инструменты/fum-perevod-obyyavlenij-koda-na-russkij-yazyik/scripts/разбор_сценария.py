class ОшибкаСценария(ValueError):
    """Не доказан закрытый синтаксис или учёт объявлений."""


@dataclass(frozen=True)
class Токен:
    текст: str
    вид: str
    начало: int
    конец: int
    строка: int
    столбец: int


def токены(текст):
    if not isinstance(текст, str) or len(текст.encode("utf-8")) > 262144:
        raise ОшибкаСценария("Превышен предел сценария")
    результат = []
    позиция, строка, столбец = 0, 1, 1
    while позиция < len(текст):
        начало = позиция
        символ = текст[позиция]
        вид = "знак"
        if символ.isspace():
            позиция += 2 if текст.startswith("\r\n", позиция) else 1
            вид = "пробел"
        elif текст.startswith("//", позиция):
            окончание = re.search(r"[\r\n\u2028\u2029]", текст[позиция:])
            позиция = позиция + окончание.start() if окончание else len(текст)
            вид = "пробел"
        elif текст.startswith("/*", позиция):
            конец = текст.find("*/", позиция + 2)
            if конец < 0:
                raise ОшибкаСценария("Незакрытый комментарий")
            позиция, вид = конец + 2, "пробел"
        elif символ in "\"'":
            позиция += 1
            while позиция < len(текст) and текст[позиция] != символ:
                if текст[позиция] == "\\":
                    if позиция + 1 < len(текст) and текст[позиция + 1] in "\r\n\u2028\u2029":
                        raise ОшибкаСценария("Продолжение строкового литерала не поддержано")
                    позиция += 2
                elif текст[позиция] in "\r\n\u2028\u2029":
                    raise ОшибкаСценария("Многострочный литерал не поддержан")
                else:
                    позиция += 1
            if позиция >= len(текст):
                raise ОшибкаСценария("Незакрытая строка")
            позиция += 1
            вид = "литерал"
        elif символ == "/" and (not результат or результат[-1].текст in {
                "(", "[", "{", ",", ":", "=", "=>", "return", "throw", "!", "?", "&&", "||", "??"}):
            позиция += 1
            класс = False
            while позиция < len(текст):
                текущий = текст[позиция]
                if текущий in "\r\n\u2028\u2029":
                    raise ОшибкаСценария("Незакрытое регулярное выражение")
                if текущий == "\\":
                    позиция += 2
                    continue
                if текущий == "[":
                    класс = True
                elif текущий == "]":
                    класс = False
                elif текущий == "/" and not класс:
                    break
                позиция += 1
            if позиция >= len(текст):
                raise ОшибкаСценария("Незакрытое регулярное выражение")
            позиция += 1
            while позиция < len(текст) and текст[позиция].isascii() and текст[позиция].isalpha():
                позиция += 1
            вид = "литерал"
        elif символ == "_" or символ == "$" or символ.isalpha():
            позиция += 1
            while позиция < len(текст) and (текст[позиция] in "_$" or текст[позиция].isalnum()):
                позиция += 1
            вид = "имя"
        elif символ.isascii() and символ.isdigit():
            число = re.match(r"(?:0[xX][0-9a-fA-F]+|0[oO][0-7]+|0[bB][01]+|[0-9]+(?:\.[0-9]*)?(?:[eE][+-]?[0-9]+)?)(?:n)?", текст[позиция:])
            позиция += len(число.group())
            вид = "литерал"
        else:
            знак = next((знак for знак in операторы if текст.startswith(знак, позиция)), None)
            if знак is None:
                raise ОшибкаСценария("Неподдержанный токен сценария")
            позиция += len(знак)
        часть = текст[начало:позиция]
        if вид != "пробел":
            результат.append(Токен(часть, вид, начало, позиция, строка, столбец))
        строки = re.split(r"\r\n|[\r\n\u2028\u2029]", часть)
        строка += len(строки) - 1
        столбец = len(строки[-1]) + 1 if len(строки) > 1 else столбец + len(часть)
    if len(результат) > 65536:
        raise ОшибкаСценария("Превышен предел токенов")
    результат.append(Токен("", "конец", позиция, позиция, строка, столбец))
    return результат


class Разбор:
    def __init__(сам, вход):
        сам.токены = вход
        сам.позиция = 0
        сам.объявления = []
        сам.пары = {}
        стек = []
        for номер, токен in enumerate(вход):
            if токен.вид == "знак" and токен.текст in {"(", "[", "{"}:
                стек.append(номер)
                if len(стек) > 64:
                    raise ОшибкаСценария("Превышена глубина сценария")
            elif токен.вид == "знак" and токен.текст in {")", "]", "}"}:
                if not стек or вход[стек[-1]].текст != {")": "(", "]": "[", "}": "{"}[токен.текст]:
                    raise ОшибкаСценария("Несогласованные скобки")
                начало = стек.pop()
                сам.пары[начало] = номер
        if стек:
            raise ОшибкаСценария("Незакрытые скобки")

    def следующий(сам, смещение=0):
        return сам.токены[min(сам.позиция + смещение, len(сам.токены) - 1)].текст

    def взять(сам, ожидаемый=None):
        токен = сам.токены[сам.позиция]
        if not токен.текст or (ожидаемый is not None and токен.текст != ожидаемый):
            raise ОшибкаСценария("Неизвестная конструкция сценария")
        сам.позиция += 1
        return токен

    def принять(сам, ожидаемый):
        if сам.следующий() == ожидаемый:
            сам.взять()
            return True
        return False

    def учесть(сам, токен, вид, внешний=None):
        сам.объявления.append({
            "имя": токен.текст, "строка": токен.строка, "столбец": токен.столбец,
            "начало": токен.начало, "конец": токен.конец,
            "вид": вид, "класс": "внешнее" if внешний else "собственное", "источник": внешний,
        })

    def имя(сам, вид):
        токен = сам.взять()
        if токен.вид != "имя" or токен.текст in служебные:
            raise ОшибкаСценария("Неподдержанное связывание")
        сам.учесть(токен, вид)
        return токен

    def поле(сам, токен):
        if токен.вид == "имя":
            сам.учесть(токен, "поле")

    def классифицировать_объект(сам, поля, развёртки):
        ключи = [сам.объявления[номер]["имя"] for номер in поля]
        форма = frozenset(ключи)
        обычная = not развёртки and форма in формы_внешних_объектов
        окружение = форма == {"PYTHONOPTIMIZE"} and развёртки == [("process", ".", "env")]
        if len(форма) != len(ключи) or not (обычная or окружение):
            return
        for номер in поля:
            запись = сам.объявления[номер]
            источник = источники_внешних_ключей.get(запись["имя"])
            if источник:
                запись.update(класс="внешнее", источник=источник)
            источник = источники_контрактных_ключей.get(запись["имя"])
            if источник:
                запись.update(класс="закреплённый-контракт", источник=источник)

    def образец(сам, вид, значение=True):
        if сам.принять("..."):
            сам.образец(вид, False)
            return
        if сам.принять("{"):
            while сам.следующий() != "}":
                if сам.принять("..."):
                    сам.имя(вид)
                else:
                    ключ = сам.взять()
                    if ключ.вид != "имя":
                        raise ОшибкаСценария("Вычисляемый ключ не поддержан")
                    if сам.принять(":"):
                        сам.учесть(ключ, "чтение-ключа")
                        сам.объявления[-1].update(класс="чтение")
                        сам.образец(вид)
                    else:
                        if ключ.вид != "имя" or ключ.текст in служебные:
                            raise ОшибкаСценария("Неизвестное связывание объекта")
                        сам.учесть(ключ, вид)
                        сам.объявления[-1]["связывание-сокращение"] = True
                        if сам.принять("="):
                            сам.выражение()
                if not сам.принять(","):
                    break
            сам.взять("}")
        elif сам.принять("["):
            while сам.следующий() != "]":
                if сам.принять(","):
                    continue
                сам.образец(вид)
                if not сам.принять(","):
                    break
            сам.взять("]")
        else:
            сам.имя(вид)
        if значение and сам.принять("="):
            сам.выражение()

    def параметры(сам):
        сам.взять("(")
        while сам.следующий() != ")":
            сам.образец("параметр")
            if not сам.принять(","):
                break
        сам.взять(")")

    def функция(сам, объявление):
        сам.взять("function")
        if объявление or сам.следующий() != "(":
            сам.имя("функция")
        сам.параметры()
        сам.блок()

    def блок(сам):
        сам.взять("{")
        while сам.следующий() != "}":
            сам.оператор()
        сам.взять("}")

    def переменные(сам):
        сам.взять()
        while True:
            сам.образец("привязка")
            if not сам.принять(","):
                break

    def оператор(сам):
        слово = сам.следующий()
        if слово == "{":
            сам.блок()
        elif сам.принять(";"):
            pass
        elif слово in {"const", "let"}:
            сам.переменные()
            сам.взять(";")
        elif слово == "function" or (слово == "async" and сам.следующий(1) == "function"):
            if слово == "async":
                начало = сам.взять()
                if начало.строка != сам.токены[сам.позиция].строка:
                    raise ОшибкаСценария("Перевод строки после async не поддержан")
            сам.функция(True)
        elif слово in {"if", "while"}:
            сам.взять()
            сам.взять("(")
            сам.выражение()
            сам.взять(")")
            сам.оператор()
            if слово == "if" and сам.принять("else"):
                сам.оператор()
        elif сам.принять("for"):
            сам.взять("(")
            if сам.следующий() in {"const", "let"}:
                сам.переменные()
            else:
                raise ОшибкаСценария("Цикл без объявления не поддержан")
            if сам.принять("of"):
                сам.выражение()
            else:
                сам.взять(";")
                if сам.следующий() != ";":
                    сам.выражение()
                сам.взять(";")
                if сам.следующий() != ")":
                    сам.выражение()
            сам.взять(")")
            сам.оператор()
        elif сам.принять("try"):
            сам.блок()
            обработан = False
            if сам.принять("catch"):
                обработан = True
                if сам.принять("("):
                    сам.образец("параметр", False)
                    сам.взять(")")
                сам.блок()
            if сам.принять("finally"):
                обработан = True
                сам.блок()
            if not обработан:
                raise ОшибкаСценария("Нет обработчика")
        elif слово in {"return", "throw"}:
            начало = сам.взять()
            if сам.следующий() != ";":
                if начало.строка != сам.токены[сам.позиция].строка:
                    raise ОшибкаСценария("Автоматическая вставка точки с запятой не поддержана")
                сам.выражение()
            сам.взять(";")
        else:
            сам.выражение()
            сам.взять(";")

    def выражение(сам, минимум=0):
        левое = сам.начало_выражения()
        while True:
            слово = сам.следующий()
            if слово in {".", "?.", "[", "(", "++", "--"}:
                if слово in {".", "?."}:
                    сам.взять()
                    ключ = сам.взять()
                    if ключ.вид != "имя":
                        raise ОшибкаСценария("Неподдержанное поле")
                    левое = (ключ, (левое[1] if левое else "<неизвестный>") + "." + ключ.текст)
                elif слово == "[":
                    сам.взять()
                    начало = сам.позиция
                    сам.выражение()
                    динамический = any(т.вид == "имя" and т.текст not in служебные
                                       for т in сам.токены[начало:сам.позиция])
                    сам.взять("]")
                    левое = (None, "динамический-индекс" if динамический else "статический-индекс")
                elif слово == "(":
                    сам.взять()
                    while сам.следующий() != ")":
                        сам.принять("...")
                        сам.выражение()
                        if not сам.принять(","):
                            break
                    сам.взять(")")
                    левое = None
                else:
                    сам.взять()
                    сам.запись(левое)
                    левое = None
                continue
            if слово == "?" and минимум <= 2:
                сам.взять()
                сам.выражение()
                сам.взять(":")
                сам.выражение(2)
                левое = None
                continue
            приоритет = приоритеты.get(слово, -1)
            if приоритет < минимум:
                break
            сам.взять()
            if приоритет == 1:
                сам.запись(левое)
            сам.выражение(приоритет if приоритет == 1 or слово == "**" else приоритет + 1)
            левое = None
        return левое

    def запись(сам, левое):
        if левое is None:
            raise ОшибкаСценария("Неподдержанная левая часть присваивания")
        токен, путь = левое
        if токен is None:
            if путь == "динамический-индекс":
                return
            raise ОшибкаСценария("Запись по статическому индексу не поддержана")
        внешний = "https://nodejs.org/api/" if путь in {"module.exports", "process.exitCode"} else None
        сам.учесть(токен, "присваивание-поля" if "." in путь else "присваивание", внешний)

    def начало_выражения(сам):
        слово = сам.следующий()
        if слово in {"!", "+", "-", "~", "typeof", "void", "delete", "await", "new"}:
            сам.взять()
            левое = сам.выражение(14)
            return левое if слово == "new" else None
        асинхронная = слово == "async" and (сам.следующий(1) in {"(", "function"} or сам.следующий(2) == "=>")
        if асинхронная:
            сам.взять()
            слово = сам.следующий()
        if слово == "function":
            сам.функция(False)
            return None
        стрелка = сам.следующий(1) == "=>" or (слово == "(" and сам.токены[сам.пары[сам.позиция] + 1].текст == "=>")
        if стрелка:
            if слово == "(":
                сам.параметры()
            else:
                сам.имя("параметр")
            сам.взять("=>")
            if сам.следующий() == "{":
                сам.блок()
            else:
                сам.выражение(1)
            return None
        if асинхронная:
            raise ОшибкаСценария("Неизвестная асинхронная конструкция")
        if сам.принять("("):
            левое = сам.выражение()
            сам.взять(")")
            return левое
        if сам.принять("["):
            while сам.следующий() != "]":
                if сам.принять(","):
                    continue
                сам.принять("...")
                сам.выражение()
                if not сам.принять(","):
                    break
            сам.взять("]")
            return None
        if сам.принять("{"):
            поля, развёртки = [], []
            while сам.следующий() != "}":
                if сам.принять("..."):
                    начало = сам.позиция
                    сам.выражение()
                    развёртки.append(tuple(т.текст for т in сам.токены[начало:сам.позиция]))
                else:
                    ключ = сам.взять()
                    if ключ.вид != "имя":
                        raise ОшибкаСценария("Вычисляемые ключи не поддержаны")
                    if сам.принять(":"):
                        поля.append(len(сам.объявления))
                        сам.поле(ключ)
                        сам.выражение()
                    elif ключ.вид != "имя" or ключ.текст in служебные:
                        raise ОшибкаСценария("Неподдержанное поле объекта")
                    else:
                        поля.append(len(сам.объявления))
                        сам.поле(ключ)
                        сам.объявления[-1]["сокращение"] = True
                if not сам.принять(","):
                    break
            сам.взять("}")
            сам.классифицировать_объект(поля, развёртки)
            return None
        токен = сам.взять()
        if токен.вид == "литерал" or токен.текст in {"true", "false", "null", "this", "undefined"}:
            return None
        if токен.вид != "имя" or токен.текст in служебные:
            raise ОшибкаСценария("Неподдержанное выражение")
        return (токен, токен.текст)


def разобрать(текст):
    разбор = Разбор(токены(текст))
    try:
        while разбор.следующий():
            разбор.оператор()
    except RecursionError as ошибка:
        raise ОшибкаСценария("Превышена глубина выражений") from ошибка
    команда = shutil.which("node")
    if not команда:
        raise ОшибкаСценария("Для синтаксической проверки требуется Node.js")
    try:
        результат = subprocess.run(
            [команда, "--check", "--input-type=commonjs"], input=текст.encode("utf-8"),
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=10,
            env={"PATH": os.defpath, "LANG": "C", "LC_ALL": "C"}, check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as ошибка:
        raise ОшибкаСценария("Node не подтвердил синтаксис") from ошибка
    if результат.returncode:
        raise ОшибкаСценария("Синтаксическая проверка Node не пройдена")
    return {"схема": "fum.объявления-сценария.1", "объявления": разбор.объявления}

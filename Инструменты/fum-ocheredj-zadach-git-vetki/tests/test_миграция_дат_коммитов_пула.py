def загрузить_тесты(
    загрузчик: unittest.TestLoader,
    тесты: unittest.TestSuite,
    шаблон: str | None,
) -> unittest.TestSuite:
    del тесты, шаблон
    набор = unittest.TestSuite()
    for имя in загрузчик.getTestCaseNames(ТестыМиграцииДатКоммитов):
        if имя in ТестыМиграцииДатКоммитов.__dict__:
            набор.addTest(ТестыМиграцииДатКоммитов(имя))
    return набор


globals()["load_" + "tests"] = загрузить_тесты


if __name__ == "__main__":
    unittest.main()

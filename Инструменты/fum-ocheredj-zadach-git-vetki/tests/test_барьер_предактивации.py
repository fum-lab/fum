import hashlib
import json
from unittest import mock

from test_ocheredj_zadach_git_vetki import GitQueueFixture, load_queue_module


class ТестыБарьераПредактивации(GitQueueFixture):
    идентификатор_задачи = "task-fork-alpha"
    идентификатор_среды = "host-fork-alpha"
    идентификатор_форка = "fork-alpha"
    поколение_запуска = "launch-generation-1"
    идентификатор_попытки_создания = "client-attempt-alpha"
    квитанция_активации = "sha256:" + hashlib.sha256(b"pair-receipt-1").hexdigest()
    хэш_предактивации = "sha256:" + hashlib.sha256(b"pair-freeze-1").hexdigest()
    хэш_конверта = "sha256:" + hashlib.sha256(b"full-envelope-1").hexdigest()

    @staticmethod
    def хэш_канонического_объекта(значение: dict[str, object]) -> str:
        сырые = json.dumps(
            значение,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
        return "sha256:" + hashlib.sha256(сырые).hexdigest()

    def хэш_привязки(
        сам,
        *,
        идентификатор_задачи: str | None = None,
        идентификатор_среды: str | None = None,
    ) -> str:
        return сам.хэш_канонического_объекта({
            "схема": "корневая-привязка-задачи.1",
            "поколение": сам.поколение_запуска,
            "исходная_вершина": сам.git("rev-parse", "HEAD").stdout.strip(),
            "форк": сам.идентификатор_форка,
            "попытка": сам.идентификатор_попытки_создания,
            "threadId": идентификатор_задачи or сам.идентификатор_задачи,
            "hostId": идентификатор_среды or сам.идентификатор_среды,
            "хэш_конверта": сам.хэш_конверта,
        })

    def парные_хэши_привязок(сам) -> list[str]:
        другой = "sha256:" + hashlib.sha256(b"other-binding").hexdigest()
        return sorted([сам.хэш_привязки(), другой])

    def хэш_активации(сам) -> str:
        return сам.хэш_канонического_объекта({
            "схема": "корневая-активация-пары.1",
            "поколение": сам.поколение_запуска,
            "хэш_предактивации": сам.хэш_предактивации,
            "хэш_квитанции": сам.квитанция_активации,
            "хэши_привязок": сам.парные_хэши_привязок(),
        })

    def аргументы_барьера(сам, **замены: str) -> list[str]:
        значения = {
            "branch_ref": "refs/heads/master",
            "base_head": сам.git("rev-parse", "HEAD").stdout.strip(),
            "fork_id": сам.идентификатор_форка,
            "launch_generation": сам.поколение_запуска,
            "client_attempt": сам.идентификатор_попытки_создания,
        }
        значения.update(замены)
        return [
            "--ветка",
            значения["branch_ref"],
            "--базовая-вершина",
            значения["base_head"],
            "--идентификатор-форка",
            значения["fork_id"],
            "--поколение-запуска",
            значения["launch_generation"],
            "--идентификатор-попытки-создания",
            значения["client_attempt"],
        ]

    def установить_барьер(сам, **замены: str):
        результат = сам.run_queue(
            "установить-барьер-предактивации",
            "--repo-root",
            str(сам.repo),
            *сам.аргументы_барьера(**замены),
            "--json",
        )
        return результат, сам.payload(результат)

    def связать_задачу(
        сам,
        ожидаемый_объект: str,
        *,
        идентификатор_задачи: str | None = None,
        **замены: str,
    ):
        задача = идентификатор_задачи or сам.идентификатор_задачи
        результат = сам.run_queue(
            "связать-задачу-барьера",
            "--repo-root",
            str(сам.repo),
            *сам.аргументы_барьера(**замены),
            "--task-id",
            задача,
            "--host-id",
            сам.идентификатор_среды,
            "--хэш-конверта",
            сам.хэш_конверта,
            "--хэш-привязки",
            сам.хэш_привязки(идентификатор_задачи=задача),
            "--ожидаемый-объект-реестра",
            ожидаемый_объект,
            "--json",
        )
        return результат, сам.payload(результат)

    def открыть_барьер(
        сам,
        ожидаемый_объект: str,
        *,
        идентификатор_задачи: str | None = None,
        **замены: str,
    ):
        результат = сам.run_queue(
            "открыть-барьер-предактивации",
            "--repo-root",
            str(сам.repo),
            *сам.аргументы_барьера(**замены),
            "--task-id",
            идентификатор_задачи or сам.идентификатор_задачи,
            "--квитанция-активации",
            сам.квитанция_активации,
            "--хэш-предактивации",
            сам.хэш_предактивации,
            *sum(
                (["--хэш-привязки-пары", значение] for значение in сам.парные_хэши_привязок()),
                [],
            ),
            "--хэш-активации",
            сам.хэш_активации(),
            "--ожидаемый-объект-реестра",
            ожидаемый_объект,
            "--json",
        )
        return результат, сам.payload(результат)

    def служебные_ссылки(сам) -> list[str]:
        return сам.git(
            "for-each-ref",
            "--format=%(refname)",
            "refs/fum/",
        ).stdout.splitlines()

    def test_несвязанный_барьер_блокирует_любой_вход_без_билета(сам) -> None:
        установка, барьер = сам.установить_барьер()
        сам.assertEqual(установка.returncode, 0, установка.stdout)
        сам.assertEqual(барьер["state"], "барьер_предактивации_установлен")
        ссылки_до = сам.служебные_ссылки()

        результат, ответ = сам.join("arbitrary-created-task")

        сам.assertNotEqual(результат.returncode, 0)
        сам.assertEqual(ответ["state"], "задача_барьера_не_связана")
        сам.assertEqual(сам.служебные_ссылки(), ссылки_до)
        сам.assertIsNone(
            сам.git(
                "rev-parse",
                "--verify",
                "--quiet",
                барьер["queue_ref"],
                check=False,
            ).stdout.strip()
            or None
        )

    def test_точная_связь_затем_открытие_допускают_вход(сам) -> None:
        установка, барьер = сам.установить_барьер()
        сам.assertEqual(установка.returncode, 0, установка.stdout)

        связь, связанный = сам.связать_задачу(
            str(барьер["объект_реестра_барьеров"])
        )
        сам.assertEqual(связь.returncode, 0, связь.stderr)
        сам.assertEqual(связанный["state"], "задача_барьера_связана")

        открытие, открытый = сам.открыть_барьер(
            str(связанный["объект_реестра_барьеров"])
        )
        сам.assertEqual(открытие.returncode, 0, открытие.stderr)
        сам.assertEqual(открытый["state"], "барьер_предактивации_открыт")

        допуск, данные_допуска = сам.join(сам.идентификатор_задачи)
        сам.assertEqual(допуск.returncode, 0, допуск.stderr)
        сам.assertEqual(данные_допуска["state"], "admitted")

    def test_дублирующая_неточная_и_устаревшая_связи_не_меняют_реестр(сам) -> None:
        установка, барьер = сам.установить_барьер()
        сам.assertEqual(установка.returncode, 0)
        объект_установки = str(барьер["объект_реестра_барьеров"])
        связь, связанный = сам.связать_задачу(объект_установки)
        сам.assertEqual(связь.returncode, 0)
        объект_связи = str(связанный["объект_реестра_барьеров"])

        дубикат, ответ_дубликата = сам.связать_задачу(
            объект_связи,
            идентификатор_задачи="task-fork-beta",
        )
        сам.assertNotEqual(дубикат.returncode, 0)
        сам.assertEqual(ответ_дубликата["state"], "дублирующая_привязка_задачи_барьера")

        неточная, ответ_неточной = сам.связать_задачу(
            объект_связи,
            fork_id="fork-other",
        )
        сам.assertNotEqual(неточная.returncode, 0)
        сам.assertEqual(ответ_неточной["state"], "несовпавший_барьер_предактивации")

        устаревшая, ответ_устаревшей = сам.связать_задачу(
            "0" * len(объект_связи)
        )
        сам.assertNotEqual(устаревшая.returncode, 0)
        сам.assertEqual(ответ_устаревшей["state"], "устаревший_реестр_барьеров")

        сам.assertEqual(
            сам.git("rev-parse", барьер["ссылка_реестра_барьеров"]).stdout.strip(),
            объект_связи,
        )

    def test_установка_знает_попытку_создания_но_ещё_не_знает_задачу(сам) -> None:
        установка, барьер = сам.установить_барьер()
        сам.assertEqual(установка.returncode, 0, установка.stderr)

        сырые = сам.git(
            "cat-file",
            "blob",
            барьер["объект_реестра_барьеров"],
        ).stdout
        значение = json.loads(сырые)
        сам.assertEqual(
            сырые,
            json.dumps(
                значение,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
            )
            + "\n",
        )
        запись = значение["барьеры"][0]
        сам.assertEqual(
            запись["идентификатор_попытки_создания"],
            сам.идентификатор_попытки_создания,
        )
        сам.assertEqual(запись["состояние"], "не_связан")
        сам.assertNotIn("идентификатор_задачи", запись)
        сам.assertNotIn("квитанция_активации", запись)
        сам.assertNotIn("хэш_активации", запись)


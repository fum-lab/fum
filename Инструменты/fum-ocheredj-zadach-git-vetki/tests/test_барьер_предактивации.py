    def test_первый_барьерный_билет_нельзя_подтвердить_на_новой_вершине(
        сам,
    ) -> None:
        установка, барьер = сам.установить_барьер()
        сам.assertEqual(установка.returncode, 0)
        связь, связанный = сам.связать_задачу(str(барьер["объект_реестра_барьеров"]))
        сам.assertEqual(связь.returncode, 0)
        открытие, _ = сам.открыть_барьер(str(связанный["объект_реестра_барьеров"]))
        сам.assertEqual(открытие.returncode, 0)
        исходная_вершина = сам.git("rev-parse", "HEAD").stdout.strip()

        модуль = load_queue_module()
        контекст = модуль.resolve_context(сам.repo)
        with mock.patch.object(
            модуль,
            "attempt_admit",
            return_value=(модуль.EXIT_WAITING, {"state": "waiting"}),
        ):
            код, _ = модуль.join_queue(контекст, сам.идентификатор_задачи)
        сам.assertEqual(код, модуль.EXIT_WAITING)

        сам.git("commit", "--allow-empty", "-m", "сдвиг между билетом и допуском")
        новая_вершина = сам.git("rev-parse", "HEAD").stdout.strip()
        подтверждение = сам.run_queue(
            "ack-head",
            "--repo-root",
            str(сам.repo),
            "--task-id",
            сам.идентификатор_задачи,
            "--head",
            новая_вершина,
            "--json",
        )
        ответ = сам.payload(подтверждение)

        сам.assertNotEqual(подтверждение.returncode, 0)
        сам.assertEqual(ответ["state"], "несовпавшая_вершина_барьера")
        состояние, _ = модуль.read_state(модуль.resolve_context(сам.repo))
        сам.assertIsNone(состояние["owner"])
        сам.assertEqual(состояние["waiting"][0]["acknowledged_head"], исходная_вершина)

    def test_первый_вход_не_пишет_билет_при_конкурентном_переключении_ветки(
        сам,
    ) -> None:
        установка, барьер = сам.установить_барьер()
        сам.assertEqual(установка.returncode, 0)
        связь, связанный = сам.связать_задачу(str(барьер["объект_реестра_барьеров"]))
        сам.assertEqual(связь.returncode, 0)
        открытие, _ = сам.открыть_барьер(str(связанный["объект_реестра_барьеров"]))
        сам.assertEqual(открытие.returncode, 0)

        модуль = load_queue_module()
        контекст = модуль.resolve_context(сам.repo)
        исходный_запуск_гит = модуль.run_git
        переключено = False

        def переключить_перед_транзакцией(каталог, аргументы, **параметры):
            nonlocal переключено
            вход = параметры.get("input_bytes") or b""
            if (
                not переключено
                and аргументы == ["update-ref", "--no-deref", "--stdin"]
                and контекст.queue_ref.encode("utf-8") in вход
            ):
                переключено = True
                сам.git("switch", "-c", "конкурентная-ветка")
            return исходный_запуск_гит(каталог, аргументы, **параметры)

        with mock.patch.object(
            модуль,
            "run_git",
            side_effect=переключить_перед_транзакцией,
        ):
            with сам.assertRaises(модуль.QueueError) as ошибка:
                модуль.join_queue(контекст, сам.идентификатор_задачи)

        сам.assertTrue(переключено)
        сам.assertEqual(ошибка.exception.state, "branch_changed")
        сам.assertIsNone(модуль.read_ref_oid(контекст, контекст.queue_ref))


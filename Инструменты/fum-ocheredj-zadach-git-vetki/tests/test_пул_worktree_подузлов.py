    def test_подмена_перенаправления_перед_транспортом_не_меняет_цель_публикации(сам) -> None:
        целевой_удалённый = сам.создать_удалённый_репозиторий("целевой-гонка-перенаправления.git")
        подменённый_удалённый = сам.создать_удалённый_репозиторий("подменённый-гонка-перенаправления.git")

    def вызвать_с_аварией_после_функции(
        сам,
        *аргументы: str,
        имя_функции: str,
        корень: Path | None = None,
        условие: Callable[[tuple[object, ...], dict[str, object], object], bool] | None = None,
        дата_коммита: str | None = None,
    ) -> object:
        модуль = сам.загрузить_сценарий_для_аварии()
        исходная_функция = getattr(модуль, имя_функции)
        авария_сработала = False
        перехваченный_результат: object | None = None

        def перехват(*позиционные: object, **именованные: object) -> object:
            nonlocal авария_сработала, перехваченный_результат
            результат = исходная_функция(*позиционные, **именованные)
            подходит = условие is None or условие(позиционные, именованные, результат)
            if подходит and not авария_сработала:
                авария_сработала = True
                перехваченный_результат = результат
                raise АварияТеста(имя_функции)
            return результат

        вывод = io.StringIO()
        with contextlib.ExitStack() as стек:
            стек.enter_context(mock.patch.object(модуль, имя_функции, side_effect=перехват))
            if дата_коммита is not None:
                стек.enter_context(
                    mock.patch.object(модуль, "выбрать_дату_коммита", return_value=дата_коммита)
                )
            with contextlib.redirect_stdout(вывод), сам.assertRaises(АварияТеста):
                модуль.главная(
                    [
                        *аргументы,
                        "--repo-root",
                        str(корень or сам.репозиторий),
                        "--json",
                    ]
                )
        сам.assertTrue(авария_сработала)
        сам.assertIsNotNone(перехваченный_результат)
        return перехваченный_результат

    def точные_даты_коммита(сам, идентификатор_коммита: str) -> tuple[str, str]:
        содержимое = сам.выполнить_команду_версий_теста(
            "cat-file",
            "commit",
            идентификатор_коммита,
        ).stdout
        строки_автора = [строка for строка in содержимое.splitlines() if строка.startswith("author ")]
        строки_коммитера = [строка for строка in содержимое.splitlines() if строка.startswith("committer ")]
        сам.assertEqual(len(строки_автора), 1)
        сам.assertEqual(len(строки_коммитера), 1)
        шаблон = re.compile(r"^[^\n]*> ([0-9]+ [+-][0-9]{4})$")
        совпадение_автора = шаблон.fullmatch(строки_автора[0])
        совпадение_коммитера = шаблон.fullmatch(строки_коммитера[0])
        сам.assertIsNotNone(совпадение_автора)
        сам.assertIsNotNone(совпадение_коммитера)
        return совпадение_автора.group(1), совпадение_коммитера.group(1)

    def хэш_канонического_объекта(сам, значение: object) -> str:
        байты = (
            json.dumps(
                значение,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
            )
            + "\n"
        ).encode("utf-8")
        return "sha256:" + hashlib.sha256(байты).hexdigest()

    def проверить_дату_коммита_по_намерению(
        сам,
        идентификатор_коммита: str,
        намерение: dict[str, object],
    ) -> None:
        дата_автора, дата_коммитера = сам.точные_даты_коммита(идентификатор_коммита)
        сам.assertEqual(дата_автора, намерение["дата_автора"])
        сам.assertEqual(дата_коммитера, намерение["дата_коммитера"])
        сам.assertEqual(дата_автора, дата_коммитера)
        сам.assertNotEqual(дата_автора, "946684800 +0000")
        эпоха, смещение = дата_автора.split()
        сам.assertEqual(смещение, "+0000")
        сам.assertGreater(int(эпоха), 946684800)
        сам.assertLess(abs(int(time.time()) - int(эпоха)), 600)


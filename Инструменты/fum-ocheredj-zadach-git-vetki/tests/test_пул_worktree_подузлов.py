        модуль = сам.загрузить_сценарий_для_аварии()
        исходный_транспорт = getattr(модуль, "выполнить_изолированную_транспортную_команду")
        перенаправление_добавлено = False

        def подменённый_транспорт(
            контекст: object,
            аргументы: list[str],
        ) -> object:
            nonlocal перенаправление_добавлено
            if аргументы[0] == "push" and not перенаправление_добавлено:
                ключ = f"url.{подменённый_удалённый}.pushInsteadOf"
                сам.выполнить_команду_версий_теста("config", "--add", ключ, str(целевой_удалённый))
                перенаправление_добавлено = True
            return исходный_транспорт(контекст, аргументы)

        вывод = io.StringIO()
        with mock.patch.object(
            модуль,
            "выполнить_изолированную_транспортную_команду",
            side_effect=подменённый_транспорт,
        ), contextlib.redirect_stdout(вывод):
            код = модуль.главная(
                [
                    "опубликовать-результат",
                    "--хэш-результата",
                    str(результат["хэш_квитанции_результата"]),
                    "--remote",
                    "origin",
                    "--task-id",
                    "task-root-гонка-перенаправления",
                    "--generation",
                    str(допуск["generation"]),
                    "--repo-root",
                    str(сам.репозиторий),
                    "--json",
                ]
            )
        сам.assertNotEqual(код, 0)
        сам.assertEqual(json.loads(вывод.getvalue())["state"], "remote_url_rewrite_forbidden")
        сам.assertTrue(перенаправление_добавлено)
        сам.assertEqual(
            сам.прочитать_ссылку_удалённого_репозитория(целевой_удалённый, ссылка),
            результат["вершина_результата"],
        )
        сам.assertIsNone(сам.прочитать_ссылку_удалённого_репозитория(подменённый_удалённый, ссылка))


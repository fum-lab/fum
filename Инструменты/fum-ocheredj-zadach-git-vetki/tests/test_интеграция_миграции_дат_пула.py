    def начальная_загрузка_из_промпта(сам, промпт: str) -> tuple[list[str], str]:
        строки = [
            строка
            for строка in промпт.splitlines()
            if строка.startswith("python3 -I -c ")
        ]
        сам.assertEqual(len(строки), 1)
        команда = shlex.split(строки[0])
        сам.assertGreaterEqual(len(команда), 6)
        сам.assertEqual(команда[:3], ["python3", "-I", "-c"])
        сам.assertEqual(команда[4], ".")
        сам.assertNotIn("__file__", команда[3])
        return команда[:5], строки[0]

    def инструмент_из_промпта(
        сам,
        промпт: str,
        *аргументы: str,
        корень: Path,
    ) -> tuple[subprocess.CompletedProcess[str], dict[str, object]]:
        начальная_загрузка, _ = сам.начальная_загрузка_из_промпта(промпт)
        результат = subprocess.run(
            [*начальная_загрузка, *аргументы],
            cwd=корень,
            check=False,
            capture_output=True,
            text=True,
        )
        нагрузка = json.loads(результат.stdout) if результат.stdout else {}
        return результат, нагрузка

    def аргументы_точного_промпта(
        сам,
        промпт: str,
        *,
        задача: str,
        таймаут: int = 5,
        ожидается_таймаут: bool = True,
    ) -> list[str]:
        _, команда = сам.начальная_загрузка_из_промпта(промпт)
        аргументы = shlex.split(команда)
        заполнитель = "${CODEX_THREAD_ID:?CODEX_THREAD_ID is required}"
        сам.assertEqual(аргументы.count(заполнитель), 1)
        аргументы[аргументы.index(заполнитель)] = задача
        if ожидается_таймаут:
            сам.assertEqual(аргументы.count("--таймаут-секунды"), 1)
            позиция_таймаута = аргументы.index("--таймаут-секунды") + 1
            сам.assertEqual(аргументы[позиция_таймаута], "86400")
            аргументы[позиция_таймаута] = str(таймаут)
        else:
            сам.assertNotIn("--таймаут-секунды", аргументы)
        return аргументы

    def запустить_точный_промпт(
        сам,
        промпт: str,
        *,
        корень: Path,
        задача: str,
    ) -> subprocess.Popen[str]:
        return subprocess.Popen(
            сам.аргументы_точного_промпта(промпт, задача=задача),
            cwd=корень,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )

    def остановить_процесс_промпта(сам, процесс: subprocess.Popen[str]) -> None:
        if процесс.poll() is not None:
            return
        процесс.terminate()
        try:
            процесс.wait(timeout=1)
        except subprocess.TimeoutExpired:
            процесс.kill()
            процесс.wait(timeout=1)


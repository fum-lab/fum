    def создать_источник_передачи(
        сам,
        *,
        задача: str,
        вызов: str,
        коммит: str,
        хэш_квитанции: str,
        назначение: str,
        эпоха: int,
        имя: str,
    ) -> Path:
        строки = запись_журнала(
            идентификатор_задачи=задача,
            идентификатор_вызова=вызов,
            идентификатор_коммита=коммит,
            хэш_квитанции=хэш_квитанции,
            эпоха_ответа=эпоха,
            состояние="committed_handoff",
            идентификатор_назначения=назначение,
        )
        записи = []
        for строка in строки:
            запись = json.loads(строка)
            нагрузка = запись.get("payload")
            if isinstance(нагрузка, dict) and нагрузка.get("type") == "custom_tool_call":
                нагрузка["input"] = нагрузка["input"].replace(
                    "зафиксировать-результат",
                    "передать-линию",
                )
            записи.append(json.dumps(запись, ensure_ascii=False, separators=(",", ":")).encode("utf-8"))
        путь = Path(сам.временный_каталог.name) / имя
        путь.write_bytes(b"\n".join(записи) + b"\n")
        return путь

    def понизить_передачу_до_исторического_дефекта(
        сам,
        *,
        назначение: str,
        родительская_задача: str,
        голова: str,
        эпоха: int,
        вызов: str,
        имя_источника: str,
    ) -> dict[str, str | Path]:
        пул = сам.состояние_пула()
        запись_назначения = пул["assignments"][назначение]
        ссылка_ветки = str(запись_назначения["branch_ref"])
        ссылка_очереди = str(запись_назначения["queue_ref"])
        ссылка_пула = сам.выполнить_команду_версий_теста(
            "for-each-ref", "--format=%(refname)", "refs/fum/worktree-subnode-pools/"
        ).stdout.strip()
        объект_пула = сам.выполнить_команду_версий_теста("rev-parse", ссылка_пула).stdout.strip()
        объект_очереди = сам.выполнить_команду_версий_теста("rev-parse", ссылка_очереди).stdout.strip()
        очередь = сам.состояние_очереди_назначения(назначение)
        исходная_квитанция = пул["session_routes"][родительская_задача]["handoff_receipt"]
        исходный_хэш = сам.хэш_канонического_объекта(исходная_квитанция)

        сырые_байты = subprocess.run(
            ["git", "-C", str(сам.репозиторий), "cat-file", "commit", голова],
            check=True,
            capture_output=True,
        ).stdout
        дефектные_байты, число_замен = re.subn(
            rb"^(author|committer) (.*>) [0-9]+ [+-][0-9]{4}$",
            rb"\1 \2 946684800 +0000",
            сырые_байты,
            flags=re.MULTILINE,
        )
        сам.assertEqual(число_замен, 2)
        дефектная_голова = subprocess.run(
            ["git", "-C", str(сам.репозиторий), "hash-object", "-t", "commit", "-w", "--stdin"],
            input=дефектные_байты,
            check=True,
            capture_output=True,
        ).stdout.decode("ascii").strip()

        пул = сам.заменить_точную_строку(пул, голова, дефектная_голова)
        очередь = сам.заменить_точную_строку(очередь, голова, дефектная_голова)

        def понизить(значение: object) -> object:
            if isinstance(значение, list):
                return [понизить(элемент) for элемент in значение]
            if not isinstance(значение, dict):
                return значение
            новое = {ключ: понизить(элемент) for ключ, элемент in значение.items()}
            if новое.get("schema") == "fum.квитанция-commit-handoff-worktree-линии.3" and новое.get("head_oid") == дефектная_голова:
                новое["schema"] = "fum.квитанция-commit-handoff-worktree-линии.2"
                новое.pop("хэш_намерения_коммита", None)
            return новое

        пул = понизить(пул)
        очередь = понизить(очередь)
        сам.assertIsInstance(пул, dict)
        сам.assertIsInstance(очередь, dict)
        историческая_квитанция = пул["session_routes"][родительская_задача]["handoff_receipt"]
        исторический_хэш = сам.хэш_канонического_объекта(историческая_квитанция)
        пул = сам.заменить_точную_строку(пул, исходный_хэш, исторический_хэш)
        очередь = сам.заменить_точную_строку(очередь, исходный_хэш, исторический_хэш)
        сам.assertIsInstance(пул, dict)
        сам.assertIsInstance(очередь, dict)
        пул["assignments"][назначение].pop("намерения_коммитов", None)
        пул["revision"] += 1
        новый_объект_пула = сам.записать_канонический_блоб(пул)
        новый_объект_очереди = сам.записать_канонический_блоб(очередь)
        среда = os.environ.copy()
        среда["GIT_COMMITTER_DATE"] = f"@{эпоха} +0000"
        среда["GIT_COMMITTER_NAME"] = "FUM Migration Test"
        среда["GIT_COMMITTER_EMAIL"] = "migration-test@example.invalid"
        транзакция = "\n".join(
            (
                "start",
                f"update {ссылка_ветки} {дефектная_голова} {голова}",
                f"update {ссылка_пула} {новый_объект_пула} {объект_пула}",
                f"update {ссылка_очереди} {новый_объект_очереди} {объект_очереди}",
                "prepare",
                "commit",
                "",
            )
        )
        subprocess.run(
            ["git", "-C", str(сам.репозиторий), "update-ref", "--create-reflog", "--stdin"],
            input=транзакция,
            text=True,
            env=среда,
            check=True,
            capture_output=True,
        )
        источник = сам.создать_источник_передачи(
            задача=родительская_задача,
            вызов=вызов,
            коммит=дефектная_голова,
            хэш_квитанции=исторический_хэш,
            назначение=назначение,
            эпоха=эпоха,
            имя=имя_источника,
        )
        return {
            "head": дефектная_голова,
            "receipt_hash": исторический_хэш,
            "source": источник,
        }

    def передать(
        сам,
        *,
        назначение: str,
        задача: str,
        поколение: str,
        продолжение: dict[str, object],
        рабочее_дерево: Path,
        имя_файла: str,
    ) -> dict[str, object]:
        цель = рабочее_дерево / "Документация/линия" / имя_файла
        цель.parent.mkdir(parents=True, exist_ok=True)
        цель.write_text(имя_файла + "\n", encoding="utf-8")
        сам.выполнить_команду_версий_теста("add", "--", str(цель.relative_to(рабочее_дерево)), корень=рабочее_дерево)
        сообщение = Path(сам.временный_каталог.name) / ("сообщение-" + имя_файла + ".txt")
        сообщение.write_text("Передать " + имя_файла + "\n", encoding="utf-8")
        _, ответ = сам.инструмент(
            "передать-линию",
            "--task-id", задача,
            "--идентификатор-назначения", назначение,
            "--поколение", поколение,
            "--хэш-продолжения", str(продолжение["хэш_продолжения"]),
            "--файл-сообщения", str(сообщение),
            корень=рабочее_дерево,
        )
        return ответ


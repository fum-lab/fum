    def закреплённый_инструмент(
        сам,
        *аргументы: str,
        корень: Path,
        ревизия_протокола: str,
        подмена: str = "нет",
        корень_идентичности: Path | None = None,
        явная_идентичность: bool = True,
        проверять: bool = True,
    ) -> tuple[subprocess.CompletedProcess[str], dict[str, object]]:
        общая_часть = (
            "import os,subprocess,sys;"
            f"p={json.dumps(ПУТЬ_СЦЕНАРИЯ_ПУЛА, ensure_ascii=False)};"
            "r=sys.argv[1];"
            "z=[k for k in os.environ if k.upper().startswith('GIT_') or "
            "k.upper().startswith('PYTHON') or k.startswith('FUM_TEST_')];"
            "[os.environ.pop(k,None) for k in z];"
            "e=dict(os.environ);"
            "e['GIT_NO_REPLACE_OBJECTS']='1';"
            "e['GIT_OPTIONAL_LOCKS']='0';"
            f"o={json.dumps(ревизия_протокола)};"
            "b=subprocess.check_output(['git','--no-replace-objects','-C',r,'show',o+':'+p],env=e,timeout=30);"
        )
        if явная_идентичность:
            код_начальной_загрузки = (
                общая_часть
                + f"путь_ядра={json.dumps(ПУТЬ_ЯДРА_МИГРАЦИИ, ensure_ascii=False)};"
                "корень_идентичности=sys.argv[2];режим_подмены=sys.argv[3];"
                "байты_ядра=subprocess.check_output(['git','--no-replace-objects','-C',r,'show',o+':'+путь_ядра],env=e,timeout=30);"
                "b=b+b'\\n# tampered script\\n' if режим_подмены=='сценарий' else b;"
                "байты_ядра=байты_ядра+b'\\n# tampered core\\n' if режим_подмены=='ядро' else байты_ядра;"
                "канонический_корень=os.path.realpath(r if корень_идентичности=='-' else корень_идентичности);"
                "globals()['_ИДЕНТИЧНОСТЬ_ЗАКРЕПЛЁННОЙ_ЗАГРУЗКИ']=(канонический_корень,o,b,байты_ядра);"
                "sys.argv=[p,*sys.argv[4:],'--repo-root',r,'--json'];"
                "exec(compile(b,p,'exec'))"
            )
            аргументы_начальной_загрузки = [
                ".",
                str(корень_идентичности.resolve()) if корень_идентичности else "-",
                подмена,
                *аргументы,
            ]
        else:
            код_начальной_загрузки = (
                общая_часть
                + "sys.argv=[p,*sys.argv[2:],'--repo-root',r];"
                "exec(compile(b,p,'exec'))"
            )
            аргументы_начальной_загрузки = [".", *аргументы, "--json"]
        результат = subprocess.run(
            [
                sys.executable,
                "-I",
                "-c",
                код_начальной_загрузки,
                *аргументы_начальной_загрузки,
            ],
            cwd=корень,
            check=False,
            capture_output=True,
            text=True,
        )
        if проверять and результат.returncode != 0:
            сам.fail(результат.stderr or результат.stdout)
        нагрузка = json.loads(результат.stdout) if результат.stdout else {}
        return результат, нагрузка


    def подготовить_фактический_кандидат_C0(
        сам,
        целевая_ссылка: str,
        результат: dict[str, object],
        *,
        дополнительные_результаты: list[dict[str, object]] | None = None,
        область_интегратора: str = "Документация/линия",
    ) -> tuple[str, str]:
        миграция = сам.состояние_пула()["миграция_дат_коммитов"]
        сам.assertEqual(миграция["status"], "completed")
        сам.assertTrue(
            сам.выполнить_команду_версий_теста(
                "merge-base", "--is-ancestor", str(миграция["tool_oid"]),
                str(результат["вершина_результата"]), проверять=False,
            ).returncode == 0
        )
        результаты = [результат, *(дополнительные_результаты or [])]
        хэши_ревью_результатов: list[str] = []
        for индекс, проверяемый_результат in enumerate(результаты):
            суффикс = "" if индекс == 0 else f"-{индекс + 1}"
            ревью_результата = сам.записать_ревью_C0_для_цели(
                идентификатор=f"ревью-фактического-результата-C0{суффикс}",
                номер=172 + индекс,
                хэш_объекта=str(
                    проверяемый_результат["хэш_квитанции_результата"]
                ),
                вершина=str(проверяемый_результат["вершина_результата"]),
                целевая_ссылка=целевая_ссылка,
            )
            хэши_ревью_результатов.append(
                str(ревью_результата["хэш_квитанции_ревью"])
            )
        база_интегратора = сам.выполнить_команду_версий_теста(
            "rev-parse", целевая_ссылка
        ).stdout.strip()
        назначение_интегратора = сам.выделить(
            "фактический-интегратор-C0",
            "поколение-фактического-интегратора-C0",
            "refs/heads/codex/подузлы/фактический-интегратор-C0",
            область_интегратора,
            роль="интегратор",
            база=база_интегратора,
            целевая_ссылка=целевая_ссылка,
        )
        сам.допустить(["фактический-интегратор-C0"], начальный_номер=180)

    def test_подмена_претензии_в_окне_чистого_завершения_не_даёт_ложный_успех(сам) -> None:
        владелец = сам.допустить("шаг-с-подменой-претензии")
        сам.установить_ограждения(владелец)
        задача = str(владелец["task_id"])
        поколение = str(владелец["generation"])
        исходная_вершина = str(владелец["base_head"])
        объект_очереди_до = МОДУЛЬ_ОЧЕРЕДИ.read_state(сам.контекст)[1]
        _, претензия = сам.прочитать_объект(сам.ссылка_претензии)  # type: ignore[misc]

        def подменить_и_потерять_ответ(*аргументы, **параметры):
            подменённая = dict(претензия)
            подменённая["schema_version"] = 6
            подменённая["step_id"] = "other-step"
            подменённая["свидетельство_чистого_завершения"] = {
                "base_head": исходная_вершина,
                "task_id": задача,
                "generation": поколение,
            }
            сам.записать_объект(сам.ссылка_претензии, подменённая)
            return subprocess.CompletedProcess(
                ["git", "update-ref"],
                1,
                b"",
                "ответ потерян".encode("utf-8"),
            )

        with mock.patch.object(
            МОДУЛЬ_ОЧЕРЕДИ,
            "update_queue_with_head_verification",
            side_effect=подменить_и_потерять_ответ,
        ):
            with сам.assertRaises(МОДУЛЬ_ОЧЕРЕДИ.QueueError) as ошибка:
                МОДУЛЬ_ОЧЕРЕДИ.finish_clean_and_handoff(
                    сам.контекст,
                    задача,
                    поколение,
                )

        сам.assertEqual(ошибка.exception.state, "next_step_clean_claim_changed")
        сам.assertEqual(МОДУЛЬ_ОЧЕРЕДИ.read_state(сам.контекст)[1], объект_очереди_до)


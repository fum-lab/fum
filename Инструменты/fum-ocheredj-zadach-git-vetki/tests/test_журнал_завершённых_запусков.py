    def выполнить_гит(
        сам,
        *аргументы: str,
        вход: str | None = None,
        проверять: bool = True,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            ["git", "-C", str(сам.корень), *аргументы],
            input=вход,
            check=проверять,
            capture_output=True,
            text=True,
        )

    def записать_объект(сам, ссылка: str, значение: dict[str, object]) -> str:
        текст = json.dumps(
            значение,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        ) + "\n"
        объект = сам.выполнить_гит(
            "hash-object", "-w", "--stdin", вход=текст
        ).stdout.strip()
        сам.выполнить_гит("update-ref", ссылка, объект)
        return объект

    def прочитать_объект(сам, ссылка: str) -> tuple[str, dict[str, object]] | None:
        результат = сам.выполнить_гит(
            "rev-parse", "--verify", "--quiet", ссылка, проверять=False
        )
        if результат.returncode != 0:
            return None
        объект = результат.stdout.strip()
        значение = json.loads(
            сам.выполнить_гит("cat-file", "blob", объект).stdout
        )
        return объект, значение


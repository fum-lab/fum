    def test_ожидающее_возобновление_схемы_четыре_не_может_записать_журнал(сам) -> None:
        владелец = сам.допустить("возобновлённый-шаг")
        сам.установить_ограждения(владелец)
        _, резервация = сам.прочитать_объект(сам.ссылка_резервации)  # type: ignore[misc]
        резервация["версия_схемы"] = 4
        резервация["возобновление"] = {"состояние": "вызов_мог_состоять"}
        сам.записать_объект(сам.ссылка_резервации, резервация)
        вершина_до = сам.выполнить_гит("rev-parse", "HEAD").stdout.strip()
        объект_очереди_до = МОДУЛЬ_ОЧЕРЕДИ.read_state(сам.контекст)[1]
        (сам.корень / "tracked.txt").write_text("pending\n", encoding="utf-8")
        сам.выполнить_гит("add", "tracked.txt")
        with сам.assertRaises(МОДУЛЬ_ОЧЕРЕДИ.QueueError):
            сам.завершить_с_коммитом(владелец, "pending\n")
        сам.assertEqual(сам.выполнить_гит("rev-parse", "HEAD").stdout.strip(), вершина_до)
        сам.assertEqual(МОДУЛЬ_ОЧЕРЕДИ.read_state(сам.контекст)[1], объект_очереди_до)
        сам.assertIsNone(сам.прочитать_объект(сам.ссылка_журнала))
        резервация["возобновление"]["состояние"] = "подтверждено_исполнителем"
        сам.записать_объект(сам.ссылка_резервации, резервация)
        код, ответ = сам.завершить_с_коммитом(владелец, "confirmed\n")
        сам.assertEqual(код, 0)
        сам.assertEqual(ответ["state"], "committed")


def загрузить_модуль(имя: str, путь: Path) -> object:
    спецификация = importlib.util.spec_from_file_location(имя, путь)
    if спецификация is None or спецификация.loader is None:
        raise AssertionError(f"Не удалось загрузить модуль {путь}.")
    модуль = importlib.util.module_from_spec(спецификация)
    sys.modules[имя] = модуль
    спецификация.loader.exec_module(модуль)
    return модуль


def собрать_записи_журнала(
    *,
    задача: str,
    вызов: str,
    назначение: str,
    идентификатор_объекта_миграции: str,
    хэш_квитанции: str,
    эпоха: int,
) -> list[bytes]:
    метка_вызова = datetime.fromtimestamp(
        эпоха - 0.125,
        tz=timezone.utc,
    ).isoformat(timespec="milliseconds").replace("+00:00", "Z")
    метка_ответа = datetime.fromtimestamp(
        эпоха + 0.875,
        tz=timezone.utc,
    ).isoformat(timespec="milliseconds").replace("+00:00", "Z")
    команда = (
        "python3 пул-worktree-подузлов.py передать-линию "
        f"--task-id {задача} --идентификатор-назначения {назначение}"
    )
    терминальный_ответ = {
        "state": "committed_handoff",
        "новая_вершина": идентификатор_объекта_миграции,
        "хэш_квитанции_передачи": хэш_квитанции,
        "идентификатор_назначения": назначение,
    }
    обёртка = {
        "exit_code": 0,
        "output": json.dumps(терминальный_ответ, ensure_ascii=False) + "\n",
    }
    записи = [
        {
            "timestamp": метка_вызова,
            "type": "session_meta",
            "payload": {"id": задача, "timestamp": метка_вызова},
        },
        {
            "timestamp": метка_вызова,
            "type": "response_item",
            "payload": {
                "type": "custom_tool_call",
                "status": "completed",
                "call_id": вызов,
                "name": "exec",
                "input": (
                    "const r = await tools.exec_command({cmd:"
                    + json.dumps(команда, ensure_ascii=False)
                    + "});"
                ),
            },
        },
        {
            "timestamp": метка_ответа,
            "type": "response_item",
            "payload": {
                "type": "custom_tool_call_output",
                "call_id": вызов,
                "output": [
                    {
                        "type": "input_text",
                        "text": json.dumps(обёртка, ensure_ascii=False),
                    }
                ],
            },
        },
    ]
    return [
        json.dumps(
            запись,
            ensure_ascii=False,
            separators=(",", ":"),
        ).encode("utf-8")
        for запись in записи
    ]



"""Парный профиль открытых кандидатов; подготовка исключена из таймера."""
import argparse
import json
import statistics
import time
import tokenize
import tracemalloc
from pathlib import Path
from unittest.mock import patch
from фикстура_русификации import Кандидат
from контракт_русификации import байты, хэш, проверить_карту
from кандидат_слияния import прочитать_кандидат
from переводчик_русификации import построить_план, проверить_контур, загрузить_контур


def ручная_последовательность(кандидат, вход, карта):
    прочитать_кандидат(кандидат.корень, вход)
    проверить_карту(карта)
    контур = проверить_контур(кандидат.корень, вход)
    стадии = []
    with загрузить_контур(кандидат.корень, контур) as (_, переводчик):
        план = переводчик.подготовить(кандидат.корень, карта['пакеты'][0]['карта'], стадии)
    прочитать_кандидат(кандидат.корень, вход)
    проверить_контур(кандидат.корень, вход)
    return {'файлы': [{'путь': п['путь'], 'результат': п['текст']} for п in план], 'стадии': стадии}


def измерить(процедура, большой_файл=None):
    чтения = []
    токенизации = []
    исходное_чтение = Path.read_bytes
    исходные_токены = tokenize.generate_tokens

    def прочитать(путь):
        данные = исходное_чтение(путь)
        чтения.append((str(путь), len(данные)))
        return данные

    def токены(*аргументы, **именованные):
        токенизации.append(time.perf_counter_ns())
        return исходные_токены(*аргументы, **именованные)

    tracemalloc.start()
    начало = time.perf_counter_ns()
    результат, ошибка = None, None
    try:
        with patch.object(Path, 'read_bytes', прочитать), patch.object(tokenize, 'generate_tokens', токены):
            результат = процедура()
    except Exception as сбой:
        ошибка = {'тип': type(сбой).__name__, 'сообщение': str(сбой)}
    конец = time.perf_counter_ns()
    _, пик = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    return {'начало_нс': начало, 'конец_нс': конец, 'длительность_нс': конец - начало,
            'пик_памяти_байты': пик, 'метод_памяти': 'tracemalloc: Python allocations, без RSS процессов Git',
            'файлов_прочитано': len({п for п, _ in чтения}), 'чтений_файлов': len(чтения),
            'байтов_прочитано': sum(б for _, б in чтения), 'граница_чтений': 'Path.read_bytes в процессе Python; Git pipe не входит',
            'чтений_большого_файла': sum(п == str(большой_файл) for п, _ in чтения),
            'токенизаций': len(токенизации), 'результат': результат, 'ошибка': ошибка}


def выполнить():
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument('--повторов', type=int, default=3)
    разборщик.add_argument('--выход', required=True)
    аргументы = разборщик.parse_args()
    if not 1 <= аргументы.повторов <= 10:
        raise ValueError('Число повторов вне конечного диапазона')
    пары = []
    for множитель in (1, 10):
        текст = 'def new_name():\n    return 7\n' + ''.join('итог' + str(и) + ' = new_name()\n' for и in range(множитель))
        к = Кандидат(текст.encode())
        try:
            вход, карта = к.вход(), к.карта()
            до = к.снимок()
            измерения = []
            for номер in range(аргументы.повторов):
                # Чередование порядка уменьшает систематическое влияние прогрева.
                порядок = ('ручная', 'автоматизация') if номер % 2 == 0 else ('автоматизация', 'ручная')
                пара = {}
                for способ in порядок:
                    стадии = []
                    процедура = (lambda: ручная_последовательность(к, вход, карта)) if способ == 'ручная' else (lambda: построить_план(к.корень, вход, карта, стадии))
                    замер = измерить(процедура)
                    if способ == 'автоматизация':
                        замер['стадии'] = стадии
                    пара[способ] = замер
                успешна = all(п['ошибка'] is None for п in пара.values())
                ошибка_пары = None if успешна else 'Неуспех одного из способов'
                if успешна:
                    обычный = {п['путь']: п['результат'] for п in пара['ручная']['результат']['файлы']}
                    новый = {п['путь']: п['результат'] for п in пара['автоматизация']['результат']['файлы']}
                    if обычный != новый or до != к.снимок():
                        ошибка_пары = 'Разные результаты либо изменение кандидата'
                измерения.append({'номер': номер + 1, 'порядок': list(порядок),
                                  'сопоставима': ошибка_пары is None, 'ошибка_пары': ошибка_пары, **пара})
            отказная = json.loads(байты(вход))
            отказная['контур']['хэш_исполнителя'] = '0' * 64
            отказ = измерить(lambda: построить_план(к.корень, отказная, карта))
            пары.append({'множитель': множитель, 'исходные_байты_utf8': текст, 'вход': вход, 'карта': карта,
                         'измерения': измерения, 'ранний_отказ': отказ})
        finally:
            к.закрыть()
    большой_текст = 'def new_name():\n    return 7\n# ' + 'x' * (1024 * 1024) + '\n'
    большой = Кандидат(большой_текст.encode())
    try:
        вход, карта = большой.вход(), большой.карта()
        вход['контур']['хэш_исполнителя'] = '0' * 64
        до = большой.снимок()
        ранний = измерить(lambda: построить_план(большой.корень, вход, карта), большой.корень / 'пример.py')
        отказ_большого = {'исходные_байты_utf8': большой_текст, 'размер': len(большой_текст.encode()),
                         'вход': вход, 'карта': карта, 'замер': ранний, 'снимок_неизменён': до == большой.снимок()}
    finally:
        большой.закрыть()
    итог = {'схема': 'fum.профиль-русификации.1', 'граница': 'Подготовка Git/карты/снимка и запись результата исключены; кэш ОС не сбрасывается.',
            'сравнение': 'Ручная последовательность принятого Python backend и новый контракт; автоматизация дополнительно проверяет delta, подтверждения и весь кандидат.',
            'пары': пары, 'отказ_большого_исходника': отказ_большого,
            'решение': 'Кэш между вызовами не вводится: он ослабил бы повторную проверку Git/исходников; ускорение не заявляется.'}
    for пара in пары:
        успешные = [п for п in пара['измерения'] if п['сопоставима']]
        пара['медианы_нс'] = {способ: statistics.median(п[способ]['длительность_нс'] for п in успешные) if успешные else None
                              for способ in ('ручная', 'автоматизация')}
    Path(аргументы.выход).write_bytes(байты(итог))
    ошибок = sum(п['ошибка_пары'] is not None for р in пары for п in р['измерения'])
    print(json.dumps({'пары': len(пары), 'повторов': аргументы.повторов,
                      'ошибок': ошибок,
                      'sha256': хэш(байты(итог))}, ensure_ascii=False))
    if (ошибок or any(р['ранний_отказ']['ошибка'] is None for р in пары) or ранний['ошибка'] is None
            or ранний['чтений_большого_файла'] or not отказ_большого['снимок_неизменён']):
        raise ValueError('Профиль сохранил неожиданный результат')


if __name__ == '__main__':
    выполнить()

import unittest
from unittest.mock import patch
from фикстура_русификации import Кандидат, хэш
from переводчик_русификации import построить_план
from контракт_русификации import Отказ, байты


class ПроверкиПлана(unittest.TestCase):
    def test_детерминированный_план_сохраняет_строки(сам):
        к = Кандидат(b'def new_name():\r\n    return "new_name" # new_name\r\n')
        сам.addCleanup(к.закрыть)
        до = к.снимок()
        план = построить_план(к.корень, к.вход(), к.карта())
        сам.assertTrue(план['допуск'])
        сам.assertEqual(план, построить_план(к.корень, к.вход(), к.карта()))
        сам.assertEqual(план['файлы'][0]['результат'].encode(),
                        'def новое_имя():\r\n    return "new_name" # new_name\r\n'.encode())
        сам.assertEqual(до, к.снимок())

    def test_неизвестное_имя_не_получает_допуск(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        карта = к.карта()
        карта['подтверждения'] = []
        from контракт_русификации import байты, хэш
        вход = к.вход()
        вход['карта_sha256'] = хэш(байты(карта))
        план = построить_план(к.корень, вход, карта)
        сам.assertFalse(план['допуск'])
        сам.assertEqual(план['запросы'][0]['имя'], 'new_name')

    def test_историческое_объявление_не_мигрируется(сам):
        прежний = b'def old_name():\n    return 3\n'
        к = Кандидат(b'def new_name():\n    return 7\n\n' + прежний, прежний=прежний)
        сам.addCleanup(к.закрыть)
        план = построить_план(к.корень, к.вход(), к.карта())
        сам.assertEqual(план['файлы'][0]['результат'].encode(), 'def новое_имя():\n    return 7\n\n'.encode() + прежний)

    def test_потребитель_и_одноимённая_локальная_привязка(сам):
        текст = 'from пример import new_name\nитог = new_name()\ndef локальная(new_name):\n    return new_name\n'
        к = Кандидат(потребитель=текст.encode())
        сам.addCleanup(к.закрыть)
        карта = к.карта()
        карта['пакеты'][0]['карта']['файлы'].append({'путь': 'потребитель.py', 'хэш': хэш(текст.encode()),
             'переводы': {}, 'области': None, 'передачи': [], 'связи': [
             {'вид': 'импорт', 'владелец': 'пример', 'имя': 'new_name', 'новое': 'новое_имя',
              'количество': 2, 'источник': 'пример.py'}]})
        вход = к.вход()
        вход['карта_sha256'] = хэш(байты(карта))
        до = к.снимок()
        план = построить_план(к.корень, вход, карта)
        итог = {п['путь']: п['результат'] for п in план['файлы']}
        сам.assertEqual(итог['потребитель.py'], 'from пример import новое_имя\nитог = новое_имя()\ndef локальная(new_name):\n    return new_name\n')
        сам.assertEqual(до, к.снимок())

    def test_неверная_позиция_не_разрешает_словарный_перевод(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        карта = к.карта()
        карта['подтверждения'][0]['столбец'] = 2
        вход = к.вход()
        вход['карта_sha256'] = хэш(байты(карта))
        до = к.снимок()
        with сам.assertRaises(Отказ):
            построить_план(к.корень, вход, карта)
        сам.assertEqual(до, к.снимок())

    def test_отсутствие_второго_контура_до_чтения_исходников(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        карта = к.карта()
        карта['пакеты'] = [{'язык': 'swift', 'карта': {'версия_схемы': 2}}]
        вход = к.вход()
        вход['карта_sha256'] = хэш(байты(карта))
        до = к.снимок()
        with patch('переводчик_русификации.исходные_байты', side_effect=AssertionError('payload не должен читаться')):
            with сам.assertRaisesRegex(Отказ, 'V2'):
                построить_план(к.корень, вход, карта)
        сам.assertEqual(до, к.снимок())

    def test_поздний_дрейф_карты_и_контура(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        вход['контур']['файлы'].pop()
        до = к.снимок()
        with сам.assertRaises(Отказ):
            построить_план(к.корень, вход, карта)
        сам.assertEqual(до, к.снимок())

    def test_перенос_строки_в_новую_область_не_история(сам):
        прежний = 'def первая():\n    legacy = 1\n'
        текст = 'def первая():\n    pass\ndef new_name():\n    legacy = 1\n'
        к = Кандидат(текст.encode(), прежний=прежний.encode())
        сам.addCleanup(к.закрыть)
        карта = к.карта()
        карта['подтверждения'][0]['строка'] = 3
        вход = к.вход()
        вход['карта_sha256'] = хэш(байты(карта))
        план = построить_план(к.корень, вход, карта)
        сам.assertFalse(план['допуск'])
        сам.assertEqual([п['имя'] for п in план['запросы']], ['legacy'])

    def test_перенос_между_генераторами_списка_не_история(сам):
        прежний = 'первая = [\n    legacy\n    for legacy in [1]\n]\n'
        текст = 'первая = []\nвторая = [\n    legacy\n    for legacy in [1]\n]\n'
        к = Кандидат(текст.encode(), прежний=прежний.encode())
        сам.addCleanup(к.закрыть)
        карта = к.карта()
        карта['подтверждения'] = []
        карта['пакеты'] = []
        вход = к.вход()
        вход['карта_sha256'] = хэш(байты(карта))
        план = построить_план(к.корень, вход, карта)
        сам.assertFalse(план['допуск'])
        сам.assertEqual([п['имя'] for п in план['запросы']], ['legacy'])

    def test_непокрытые_объявления_не_получают_пустой_допуск(сам):
        for текст in ('match 1:\n    case legacy:\n        pass\n', 'def é():\n    return 7\n', 'новоеé = 1\n', 'новоеe\u0301 = 1\n'):
            with сам.subTest(текст=текст):
                к = Кандидат(текст.encode())
                try:
                    карта = к.карта()
                    карта['подтверждения'] = []
                    карта['пакеты'] = []
                    вход = к.вход()
                    вход['карта_sha256'] = хэш(байты(карта))
                    до = к.снимок()
                    with сам.assertRaises(Отказ):
                        построить_план(к.корень, вход, карта)
                    сам.assertEqual(до, к.снимок())
                finally:
                    к.закрыть()

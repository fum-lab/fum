import unittest
from unittest.mock import patch
from фикстура_русификации import Кандидат, гит
from контракт_русификации import Отказ, разобрать, проверить_вход, проверить_карту
from кандидат_слияния import прочитать_кандидат, исходные_байты


class ПроверкиКонтракта(unittest.TestCase):
    def test_повторные_и_неизвестные_поля(сам):
        with сам.assertRaises(Отказ):
            разобрать(b'{"x":1,"x":2}')
        with сам.assertRaises(Отказ):
            проверить_вход({'схема': 'чужая'})

    def test_кандидат_и_отказ_без_записи(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        до = к.снимок()
        результат = прочитать_кандидат(к.корень, к.вход())
        сам.assertEqual(результат['изменённые'], ['пример.py'])
        сам.assertEqual(до, к.снимок())
        вход = к.вход()
        вход['источник'] = '0' * 40
        with сам.assertRaises(Отказ):
            прочитать_кандидат(к.корень, вход)
        сам.assertEqual(до, к.снимок())

    def test_смешанная_латиница_и_неверные_типы(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        for новое in ('новоеé', 'новоеＡ', 'новое𝐱'):
            карта = к.карта()
            карта['подтверждения'][0]['новое'] = новое
            with сам.subTest(новое=новое), сам.assertRaises(Отказ):
                проверить_карту(карта)
        for область in ([[]], ['пример.py', 'ПРИМЕР.py']):
            вход = к.вход()
            вход['область'] = область
            with сам.subTest(область=область), сам.assertRaises(Отказ):
                проверить_вход(вход)

    def test_скрытые_флаги_и_разделённый_индекс(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        for флаг in ('--assume-unchanged', '--skip-worktree'):
            гит(к.корень, 'update-index', флаг, 'пример.py')
            вход = к.вход()
            до = к.снимок()
            with сам.assertRaises(Отказ):
                прочитать_кандидат(к.корень, вход)
            сам.assertEqual(до, к.снимок())
            гит(к.корень, 'update-index', флаг.replace('--', '--no-', 1), 'пример.py')
        гит(к.корень, 'update-index', '--split-index')
        вход = к.вход()
        до = к.снимок()
        with сам.assertRaises(Отказ):
            прочитать_кандидат(к.корень, вход)
        сам.assertEqual(до, к.снимок())

    def test_подмена_объекта_не_меняет_истинные_байты(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход = к.вход()
        снимок = прочитать_кандидат(к.корень, вход)
        объект = next(п['blob'] for п in снимок['индекс']['записи'] if п['путь'] == 'пример.py')
        (к.корень / 'пример.py').write_bytes(b'def replacement():\n    return 9\n')
        подмена = гит(к.корень, 'hash-object', '-w', 'пример.py').decode().strip()
        гит(к.корень, 'replace', объект, подмена)
        до = к.снимок()
        with сам.assertRaises(Отказ):
            исходные_байты(к.корень, снимок, 'пример.py')
        сам.assertEqual(до, к.снимок())

    def test_поздний_дрейф_сливаемой_вершины(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход = к.вход()
        import кандидат_слияния
        штатный = кандидат_слияния.гит

        def с_дрейфом(корень, *аргументы):
            if аргументы[0] == 'diff':
                (корень / '.git/MERGE_HEAD').write_text('0' * 40 + '\n')
            return штатный(корень, *аргументы)

        with patch('кандидат_слияния.гит', side_effect=с_дрейфом):
            with сам.assertRaises(Отказ):
                прочитать_кандидат(к.корень, вход)
        сам.assertEqual((к.корень / '.git/MERGE_HEAD').read_text(), '0' * 40 + '\n')

    def test_символическая_ссылка_и_неверный_режим(сам):
        к = Кандидат(режим=0o755)
        сам.addCleanup(к.закрыть)
        снимок = прочитать_кандидат(к.корень, к.вход())
        файл = к.корень / 'пример.py'
        файл.chmod(0o654)
        with сам.assertRaises(Отказ):
            исходные_байты(к.корень, снимок, 'пример.py')
        файл.unlink()
        файл.symlink_to('потребитель.py')
        with сам.assertRaises(Отказ):
            исходные_байты(к.корень, снимок, 'пример.py')

import subprocess
import sys
import unittest
from unittest.mock import patch
from pathlib import Path
from фикстура_русификации import Кандидат, КАТАЛОГ, гит
from контракт_русификации import Отказ, байты, разобрать
from переводчик_русификации import построить_план
from транзакция_русификации import применить
from свидетельство_русификации import проверить, снять_свидетельство


class ПроверкиПодключения(unittest.TestCase):
    def test_самосогласованный_пустой_план_не_приёмка(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        план['файлы'] = []
        до = к.снимок()
        with сам.assertRaises(Отказ):
            снять_свидетельство(к.корень, вход, карта, план, 'после-применения')
        сам.assertEqual(до, к.снимок())

    def test_подмена_состава_сырого_индекса(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        план['индекс']['записи'][0]['blob'] = '0' * 40
        with сам.assertRaises(Отказ):
            снять_свидетельство(к.корень, вход, карта, план, 'после-применения')

    def test_поздний_дрейф_при_чтении_свидетельства(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        квитанция = применить(к.корень, вход, карта, план, к.состояние)
        штатное = Path.read_bytes

        def прочитать(путь):
            данные = штатное(путь)
            if путь == к.корень / 'пример.py':
                (к.корень / '.git/MERGE_HEAD').write_text('0' * 40 + '\n')
            return данные

        with patch.object(Path, 'read_bytes', прочитать):
            with сам.assertRaises(Отказ):
                проверить(к.корень, вход, карта, план, квитанция, 'после-применения')
        сам.assertEqual((к.корень / '.git/MERGE_HEAD').read_text(), '0' * 40 + '\n')

    def test_точное_стадирование_и_посторонний_файл(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        квитанция = применить(к.корень, вход, карта, план, к.состояние)
        with сам.assertRaises(Отказ):
            проверить(к.корень, вход, карта, план, квитанция, 'перед-коммитом')
        гит(к.корень, 'add', 'пример.py')
        свидетельство = проверить(к.корень, вход, карта, план, квитанция, 'перед-коммитом')
        сам.assertEqual(свидетельство['родители'], [к.принимающий, к.источник])
        (к.корень / 'лишний.py').write_bytes(b'# unexpected\n')
        гит(к.корень, 'add', 'лишний.py')
        до = к.снимок()
        with сам.assertRaises(Отказ):
            проверить(к.корень, вход, карта, план, квитанция, 'перед-коммитом')
        сам.assertEqual(до, к.снимок())

    def test_командный_интерфейс_кандидата_без_коммита(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        for имя, данные in [('вход', вход), ('карта', карта)]:
            (к.корень.parent / (имя + '.json')).write_bytes(байты(данные))
        базовые = [sys.executable, '-B', str(КАТАЛОГ / 'scripts/русифицировать-код-при-слиянии.py'),
                   '--корень-репозитория', str(к.корень), '--вход', str(к.корень.parent / 'вход.json'),
                   '--карта', str(к.корень.parent / 'карта.json')]
        до = к.снимок()
        процесс = subprocess.run(базовые + ['план'], capture_output=True, check=True)
        план = разобрать(процесс.stdout)
        сам.assertEqual(до, к.снимок())
        (к.корень.parent / 'план.json').write_bytes(процесс.stdout)
        процесс = subprocess.run(базовые + ['применить', '--план', str(к.корень.parent / 'план.json'),
                                '--состояние', str(к.состояние)], capture_output=True, check=True)
        сам.assertTrue(разобрать(процесс.stdout)['допуск'])
        сам.assertEqual(до[:6], к.снимок()[:6])
        сам.assertEqual((к.корень / 'пример.py').read_bytes(), 'def новое_имя():\n    return 7\n'.encode())

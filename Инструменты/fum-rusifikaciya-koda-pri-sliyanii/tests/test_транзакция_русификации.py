import unittest
import subprocess
import sys
from unittest.mock import patch
from фикстура_русификации import Кандидат, КАТАЛОГ
from переводчик_русификации import построить_план
from транзакция_русификации import применить, восстановить
from свидетельство_русификации import проверить
from контракт_русификации import Отказ, разобрать, байты


class ПроверкиТранзакции(unittest.TestCase):
    def test_применение_повтор_и_независимые_байты(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        до = к.снимок()
        план = построить_план(к.корень, вход, карта)
        квитанция = применить(к.корень, вход, карта, план, к.состояние)
        сам.assertEqual((к.корень / 'пример.py').read_bytes(), 'def новое_имя():\n    return 7\n'.encode())
        сам.assertEqual(до[:6], к.снимок()[:6])
        сам.assertEqual(квитанция, применить(к.корень, вход, карта, план, к.состояние))
        сам.assertTrue(проверить(к.корень, вход, карта, план, квитанция, 'после-применения')['допуск'])

    def test_дрейф_до_применения_без_эффекта(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        (к.корень / 'пример.py').write_bytes(b'# foreign bytes\n')
        до = к.снимок()
        with сам.assertRaises(Отказ):
            применить(к.корень, вход, карта, план, к.состояние)
        сам.assertEqual(до, к.снимок())
        сам.assertFalse(к.состояние.exists())

    def test_повреждённый_план_без_эффекта(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        план['файлы'][0]['результат'] = 'другие байты'
        до = к.снимок()
        with сам.assertRaises(Отказ):
            применить(к.корень, вход, карта, план, к.состояние)
        сам.assertEqual(до, к.снимок())
        сам.assertFalse(к.состояние.exists())

    def test_явное_восстановление_сохраняет_режим(сам):
        к = Кандидат(режим=0o755)
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        import транзакция_русификации
        штатная = транзакция_русификации.заменить_байты

        def прервать(путь, данные, режим):
            штатная(путь, данные, режим)
            if путь.name == 'пример.py':
                raise RuntimeError('Доказанное прерывание после замены')

        with patch('транзакция_русификации.заменить_байты', side_effect=прервать):
            with сам.assertRaises(RuntimeError):
                применить(к.корень, вход, карта, план, к.состояние)
        до = к.снимок()
        with сам.assertRaises(Отказ):
            применить(к.корень, вход, карта, план, к.состояние)
        сам.assertEqual(до, к.снимок())
        квитанция = восстановить(к.корень, вход, карта, план, к.состояние)
        сам.assertTrue(квитанция['допуск'])
        сам.assertEqual((к.корень / 'пример.py').stat().st_mode & 0o777, 0o755)
        сам.assertEqual((к.корень / 'пример.py').read_bytes(), 'def новое_имя():\n    return 7\n'.encode())

    def test_восстановление_не_перезаписывает_третьи_байты(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        применить(к.корень, вход, карта, план, к.состояние)
        (к.корень / 'пример.py').write_bytes(b'# foreign bytes\n')
        до = к.снимок()
        намерение = (к.состояние / 'намерение.json').read_bytes()
        with сам.assertRaises(Отказ):
            восстановить(к.корень, вход, карта, план, к.состояние)
        сам.assertEqual(до, к.снимок())
        сам.assertEqual(намерение, (к.состояние / 'намерение.json').read_bytes())

    def test_завершённая_попытка_не_перезапускается_из_до(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        применить(к.корень, вход, карта, план, к.состояние)
        (к.корень / 'пример.py').write_bytes(b'def new_name():\n    return 7\n')
        до = к.снимок()
        with сам.assertRaises(Отказ):
            восстановить(к.корень, вход, карта, план, к.состояние)
        сам.assertEqual(до, к.снимок())

    def test_повреждённое_терминальное_свидетельство_не_переписывается(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        применить(к.корень, вход, карта, план, к.состояние)
        файл = к.состояние / 'намерение.json'
        запись = разобрать(файл.read_bytes())
        запись['свидетельство'] = {}
        файл.write_bytes(байты(запись))
        до, намерение = к.снимок(), файл.read_bytes()
        with сам.assertRaises(Отказ):
            восстановить(к.корень, вход, карта, план, к.состояние)
        сам.assertEqual(до, к.снимок())
        сам.assertEqual(намерение, файл.read_bytes())

    def test_авария_процесса_и_сохранённый_замок(сам):
        к = Кандидат()
        сам.addCleanup(к.закрыть)
        вход, карта = к.вход(), к.карта()
        план = построить_план(к.корень, вход, карта)
        for имя, данные in [('вход', вход), ('карта', карта), ('план', план)]:
            (к.корень.parent / (имя + '.json')).write_bytes(байты(данные))
        код = '''import os, sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
import транзакция_русификации as транзакция
from контракт_русификации import разобрать
корень = Path(sys.argv[2])
данные = [разобрать((корень.parent / (имя + '.json')).read_bytes()) for имя in ('вход', 'карта', 'план')]
штатная = транзакция.заменить_байты
def заменить(путь, данные, режим):
    штатная(путь, данные, режим)
    if путь.name == 'пример.py':
        os._exit(73)
транзакция.заменить_байты = заменить
транзакция.применить(корень, *данные, корень.parent / 'транзакция')
'''
        процесс = subprocess.run([sys.executable, '-B', '-c', код, str(КАТАЛОГ / 'scripts'), str(к.корень)], capture_output=True)
        сам.assertEqual(процесс.returncode, 73, процесс.stderr.decode())
        сам.assertTrue((к.состояние / 'замок.json').is_file())
        до = к.снимок()
        with сам.assertRaises(Отказ):
            применить(к.корень, вход, карта, план, к.состояние)
        сам.assertEqual(до, к.снимок())
        сам.assertTrue(восстановить(к.корень, вход, карта, план, к.состояние)['допуск'])
        сам.assertFalse((к.состояние / 'замок.json').exists())

"""Читать обычный кандидат, не создавать деревьев или Git-объектов."""
import os
import base64
import hashlib
import struct
import stat
import subprocess
from pathlib import Path
from контракт_русификации import Отказ, хэш, требовать, проверить_вход, точный_файл, поля


def разобрать_сырой_индекс(данные):
    требовать(len(данные) >= 32 and данные[:4] == b'DIRC' and hashlib.sha1(данные[:-20]).digest() == данные[-20:], 'Повреждён сырой индекс')
    версия, количество = struct.unpack('>II', данные[4:12])
    требовать(версия in {2, 3} and количество <= 500000, 'Поддержаны только обычные индексы v2/v3')
    записи, позиция = [], 12
    for _ in range(количество):
        начало = позиция
        требовать(позиция + 62 < len(данные) - 20, 'Обрыв записи индекса')
        режим = struct.unpack('>I', данные[позиция + 24:позиция + 28])[0]
        объект = данные[позиция + 40:позиция + 60].hex()
        флаги = struct.unpack('>H', данные[позиция + 60:позиция + 62])[0]
        требовать(not флаги & 0xb000, 'Конфликт или скрывающий флаг сырого индекса')
        позиция += 62
        if флаги & 0x4000:
            требовать(версия == 3 and данные[позиция:позиция + 2] == b'\0\0', 'Расширенные флаги индекса закрыты')
            позиция += 2
        конец = данные.find(b'\0', позиция, len(данные) - 20)
        требовать(конец > позиция, 'Нет имени индекса')
        имя = данные[позиция:конец].decode('utf-8')
        требовать(флаги & 0x0fff == min(конец - позиция, 0x0fff), 'Иная длина имени индекса')
        позиция = начало + ((конец + 1 - начало + 7) // 8) * 8
        требовать(not any(данные[конец:позиция]), 'Неверное дополнение индекса')
        записи.append({'путь': имя, 'режим': format(режим, 'o'), 'blob': объект})
    while позиция < len(данные) - 20:
        требовать(позиция + 8 <= len(данные) - 20, 'Обрыв расширения индекса')
        имя = данные[позиция:позиция + 4]
        размер = struct.unpack('>I', данные[позиция + 4:позиция + 8])[0]
        требовать(65 <= имя[0] <= 90, 'Неизвестное обязательное расширение индекса')
        позиция += 8 + размер
    требовать(позиция == len(данные) - 20, 'Обрыв хвоста индекса')
    return записи


def проверить_снимок_индекса(снимок, ожидаемый_хэш):
    поля(снимок, {'sha256', 'байты', 'записи'})
    данные = base64.b64decode(снимок['байты'], validate=True)
    требовать(хэш(данные) == ожидаемый_хэш == снимок['sha256']
              and разобрать_сырой_индекс(данные) == снимок['записи'], 'Состав не соответствует исходным байтам индекса')
    return снимок


def гит(корень, *аргументы):
    запрещены = {'GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR', 'GIT_OBJECT_DIRECTORY',
                 'GIT_ALTERNATE_OBJECT_DIRECTORIES', 'GIT_CONFIG_PARAMETERS', 'GIT_CONFIG_COUNT',
                 'GIT_REPLACE_REF_BASE', 'GIT_SHALLOW_FILE', 'GIT_NAMESPACE'}
    требовать(not запрещены.intersection(os.environ), 'Перенаправление Git запрещено')
    try:
        среда = {к: з for к, з in os.environ.items() if not к.startswith('GIT_')}
        среда.update(GIT_NO_REPLACE_OBJECTS='1', GIT_NO_LAZY_FETCH='1', GIT_CONFIG_NOSYSTEM='1',
                     GIT_CONFIG_GLOBAL='/dev/null', GIT_TERMINAL_PROMPT='0')
        return subprocess.check_output(['git', '--no-optional-locks', '-c', 'core.fsmonitor=false',
                                       '-c', 'core.hooksPath=/dev/null', '-c', 'submodule.recurse=false',
                                       '-C', str(корень), *аргументы],
                                       stderr=subprocess.PIPE, timeout=30, env=среда)
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as ошибка:
        raise Отказ('Не подтверждена читающая граница Git') from ошибка


def прочитать_индекс(корень):
    имя = гит(корень, 'rev-parse', '--git-path', 'index').decode().strip()
    путь = Path(имя) if Path(имя).is_absolute() else корень / имя
    требовать(not путь.is_symlink() and stat.S_ISREG(путь.stat().st_mode), 'Неверный файл индекса')
    требовать(not гит(корень, 'rev-parse', '--shared-index-path').strip(), 'Split index не входит в первый контракт')
    данные = путь.read_bytes()
    записи = []
    for сырой in гит(корень, 'ls-files', '--stage', '-z').split(b'\0'):
        if not сырой:
            continue
        свойства, имя = сырой.split(b'\t', 1)
        режим, объект, стадия = свойства.decode().split()
        требовать(стадия == '0', 'Неисправленный конфликт индекса')
        записи.append({'путь': имя.decode('utf-8'), 'режим': режим, 'blob': объект})
    for сырой in гит(корень, 'ls-files', '-v', '-z').split(b'\0'):
        if сырой:
            требовать(сырой[:1] == b'H', 'Скрытые флаги или sparse index не поддержаны')
    требовать(путь.read_bytes() == данные, 'Индекс изменился при чтении')
    требовать(разобрать_сырой_индекс(данные) == записи, 'Читающая граница индекса не совпала')
    return {'sha256': хэш(данные), 'байты': base64.b64encode(данные).decode('ascii'), 'записи': записи}


def прочитать_кандидат(корень, вход, итоговый_индекс=False):
    проверить_вход(вход)
    корень = Path(корень)
    требовать(корень.is_absolute() and корень == корень.resolve(strict=True), 'Неверный физический корень')
    требовать(гит(корень, 'rev-parse', '--show-toplevel').decode().strip() == str(корень), 'Не корень checkout')
    требовать(гит(корень, 'rev-parse', '--show-object-format').strip() == b'sha1', 'Не поддержанный формат Git OID')
    for имя in ('принимающий', 'источник'):
        требовать(гит(корень, 'cat-file', '-t', вход[имя]).strip() == b'commit', 'OID не является коммитом')
    требовать(гит(корень, 'rev-parse', 'HEAD').decode().strip() == вход['принимающий'], 'HEAD изменился')
    требовать(гит(корень, 'symbolic-ref', 'HEAD').strip(), 'Detached HEAD кандидата')
    имя = Path(гит(корень, 'rev-parse', '--git-path', 'MERGE_HEAD').decode().strip())
    if not имя.is_absolute():
        имя = корень / имя
    требовать(имя.is_file() and not имя.is_symlink(), 'Нет обычного MERGE_HEAD')
    требовать(имя.read_bytes() == (вход['источник'] + '\n').encode(), 'Нет единственного ожидаемого MERGE_HEAD')
    for операция in ('rebase-merge', 'rebase-apply', 'CHERRY_PICK_HEAD', 'REVERT_HEAD'):
        путь = Path(гит(корень, 'rev-parse', '--git-path', операция).decode().strip())
        if not путь.is_absolute():
            путь = корень / путь
        требовать(not путь.exists(), 'Другая незавершённая Git-операция')
    индекс = прочитать_индекс(корень)
    if not итоговый_индекс:
        требовать(индекс['sha256'] == вход['индекс_sha256'], 'Индекс изменился после постановки')
    изменённые = [п.decode('utf-8') for п in гит(корень, 'diff', '--cached', '--name-only', '-z',
                                               '--no-renames', '--no-ext-diff', '--no-textconv', вход['принимающий']).split(b'\0') if п]
    требовать(гит(корень, 'rev-parse', 'HEAD').decode().strip() == вход['принимающий']
              and имя.read_bytes() == (вход['источник'] + '\n').encode()
              and прочитать_индекс(корень) == индекс, 'Кандидат изменился при чтении')
    return {'индекс': индекс, 'изменённые': sorted(изменённые)}


def исходные_байты(корень, снимок, имя):
    записи = [п for п in снимок['индекс']['записи'] if п['путь'] == имя]
    требовать(len(записи) == 1 and записи[0]['режим'] in {'100644', '100755'}, 'Не обычный stage-0 исходник')
    файл = точный_файл(корень, имя)
    данные = файл.read_bytes()
    требовать(данные == гит(корень, 'cat-file', 'blob', записи[0]['blob']), 'Рабочие байты не совпадают с кандидатом')
    требовать(bool(файл.stat().st_mode & stat.S_IXUSR) == (записи[0]['режим'] == '100755'), 'Режим расходится с индексом')
    return данные

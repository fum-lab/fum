"""Долговечное намерение и явное восстановление известного префикса."""
import base64
import os
import stat
import tempfile
from contextlib import contextmanager
from pathlib import Path
from контракт_русификации import Отказ, байты, хэш, требовать, разобрать, поля, точный_файл
from кандидат_слияния import гит, прочитать_кандидат
from переводчик_русификации import построить_план, проверить_контур
from свидетельство_русификации import снять_свидетельство


def синхронизировать_каталог(путь):
    дескриптор = os.open(путь, os.O_RDONLY)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def заменить_байты(путь, данные, режим):
    дескриптор, имя = tempfile.mkstemp(prefix='.fum-русификация-', dir=путь.parent)
    try:
        with os.fdopen(дескриптор, 'wb') as файл:
            os.fchmod(файл.fileno(), режим)
            файл.write(данные)
            файл.flush()
            os.fsync(файл.fileno())
        os.replace(имя, путь)
        синхронизировать_каталог(путь.parent)
    finally:
        if os.path.lexists(имя):
            os.unlink(имя)


def внешний_каталог(корень, каталог):
    корень, каталог = Path(корень), Path(каталог)
    требовать(каталог.is_absolute() and каталог.parent == каталог.parent.resolve(strict=True), 'Нужен точный внешний каталог')
    общий = Path(гит(корень, 'rev-parse', '--git-common-dir').decode().strip())
    if not общий.is_absolute():
        общий = корень / общий
    требовать(not каталог.is_relative_to(корень) and not каталог.is_relative_to(общий.resolve()), 'Состояние внутри checkout/Git запрещено')
    требовать(not каталог.is_symlink(), 'Ссылка вместо состояния')
    if каталог.exists():
        требовать(каталог.is_dir() and каталог == каталог.resolve(strict=True), 'Неверный каталог состояния')
    return каталог


@contextmanager
def замок(каталог, восстановление=False):
    путь = каталог / 'замок.json'
    if путь.exists() or путь.is_symlink():
        требовать(восстановление and not путь.is_symlink() and путь.stat().st_nlink == 1, 'Транзакция занята или неизвестна')
        прежний = разобрать(путь.read_bytes())
        поля(прежний, {'процесс'})
        требовать(type(прежний['процесс']) is int and прежний['процесс'] > 0, 'Неверный владелец замка')
        try:
            os.kill(прежний['процесс'], 0)
        except ProcessLookupError:
            путь.unlink()
        else:
            raise Отказ('Прежний процесс ещё существует')
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(дескриптор, 'wb') as файл:
            файл.write(байты({'процесс': os.getpid()}))
            файл.flush()
            os.fsync(файл.fileno())
        синхронизировать_каталог(каталог)
        yield
    finally:
        путь.unlink()
        синхронизировать_каталог(каталог)


def прочитать_состояние(каталог, корень, вход, карта, план):
    путь = каталог / 'намерение.json'
    требовать(путь.is_file() and not путь.is_symlink() and путь.stat().st_nlink == 1, 'Нет точного намерения')
    запись = разобрать(путь.read_bytes())
    поля(запись, {'схема', 'корень', 'хэш_входа', 'хэш_карты', 'хэш_плана', 'фаза', 'исходники', 'свидетельство'})
    требовать(запись['схема'] == 'fum.транзакция-русификации.1' and запись['корень'] == str(корень)
              and запись['хэш_входа'] == хэш(байты(вход)) and запись['хэш_карты'] == хэш(байты(карта))
              and запись['хэш_плана'] == хэш(байты(план)), 'Прежнее намерение не принадлежит этому плану')
    требовать(запись['фаза'] in {'подготовлена', 'применение', 'завершена'}, 'Неверная фаза намерения')
    требовать(set(запись['исходники']) == {п['путь'] for п in план['файлы']}, 'Неполный снимок намерения')
    for файл in план['файлы']:
        исходник = base64.b64decode(запись['исходники'][файл['путь']], validate=True)
        требовать(хэш(исходник) == файл['до'], 'Повреждён исходный снимок')
    return запись


def проверить_префикс(корень, вход, план):
    прочитать_кандидат(корень, вход)
    проверить_контур(корень, вход)
    результаты = {п['путь']: п['после'] for п in план['файлы']}
    for файл in план['исходники']:
        путь = точный_файл(корень, файл['путь'])
        требовать(хэш(путь.read_bytes()) in {файл['хэш'], результаты.get(файл['путь'])}
                  and путь.stat().st_mode & 0o777 == файл['режим_файла'], 'Третьи байты или режим закрывают восстановление')


def завершить(корень, вход, карта, план, каталог, запись):
    проверить_префикс(корень, вход, план)
    требовать(план == построить_план(корень, вход, карта, из_индекса=True), 'Исходный план не воспроизводится из Git')
    запись['фаза'] = 'применение'
    заменить_байты(каталог / 'намерение.json', байты(запись), 0o600)
    for файл in план['файлы']:
        проверить_префикс(корень, вход, план)
        путь = точный_файл(корень, файл['путь'])
        if хэш(путь.read_bytes()) == файл['до']:
            заменить_байты(путь, файл['результат'].encode('utf-8'), файл['режим_файла'])
    свидетельство = снять_свидетельство(корень, вход, карта, план, 'после-применения')
    запись.update(фаза='завершена', свидетельство=свидетельство)
    заменить_байты(каталог / 'намерение.json', байты(запись), 0o600)
    return свидетельство


def применить(корень, вход, карта, план, каталог):
    корень = Path(корень)
    каталог = внешний_каталог(корень, каталог)
    if каталог.exists():
        with замок(каталог):
            запись = прочитать_состояние(каталог, корень, вход, карта, план)
            требовать(запись['фаза'] == 'завершена', 'Незавершённая попытка требует явного восстановления')
            требовать(план == построить_план(корень, вход, карта, из_индекса=True), 'Прежний план не воспроизводится')
            результат = снять_свидетельство(корень, вход, карта, план, 'после-применения')
            требовать(запись['свидетельство'] == результат, 'Прежний результат изменился')
            return результат
    требовать(план == построить_план(корень, вход, карта) and план['допуск'] is True, 'План не подтверждён')
    исходники = {п['путь']: base64.b64encode(точный_файл(корень, п['путь']).read_bytes()).decode('ascii') for п in план['файлы']}
    каталог.mkdir(mode=0o700)
    синхронизировать_каталог(каталог.parent)
    with замок(каталог):
        запись = {'схема': 'fum.транзакция-русификации.1', 'корень': str(корень),
                  'хэш_входа': хэш(байты(вход)), 'хэш_карты': хэш(байты(карта)),
                  'хэш_плана': хэш(байты(план)), 'фаза': 'подготовлена', 'исходники': исходники, 'свидетельство': None}
        заменить_байты(каталог / 'намерение.json', байты(запись), 0o600)
        return завершить(корень, вход, карта, план, каталог, запись)


def восстановить(корень, вход, карта, план, каталог):
    корень = Path(корень)
    каталог = внешний_каталог(корень, каталог)
    with замок(каталог, восстановление=True):
        запись = прочитать_состояние(каталог, корень, вход, карта, план)
        if запись['фаза'] == 'завершена':
            результат = снять_свидетельство(корень, вход, карта, план, 'после-применения')
            требовать(результат == запись['свидетельство'], 'Завершённая транзакция изменилась')
            return результат
        return завершить(корень, вход, карта, план, каталог, запись)

"""Закрытые входы и байтовые границы отдельной процедуры русификации."""
import hashlib
import json
import re
import keyword
import stat
import unicodedata
from pathlib import Path, PurePosixPath


class Отказ(ValueError):
    """Неподтверждённый вход не разрешает запись."""


def требовать(условие, причина):
    if not условие:
        raise Отказ(причина)


def поля(объект, ожидаемые):
    требовать(type(объект) is dict and set(объект) == set(ожидаемые), 'Неизвестные или отсутствующие поля')


def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def байты(данные):
    return (json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def без_повторов(пары):
    результат = {}
    for имя, значение in пары:
        требовать(имя not in результат, 'Повторное поле JSON')
        результат[имя] = значение
    return результат


def разобрать(данные):
    try:
        return json.loads(данные.decode('utf-8'), object_pairs_hook=без_повторов,
                          parse_constant=lambda значение: (_ for _ in ()).throw(Отказ('Недопустимое число JSON')))
    except (UnicodeError, json.JSONDecodeError) as ошибка:
        raise Отказ('Некорректный JSON/UTF-8') from ошибка


def проверить_хэш(значение, длина=64):
    требовать(type(значение) is str and re.fullmatch('[0-9a-f]{' + str(длина) + '}', значение), 'Неверный полный хэш')


def имя_пути(имя, каталог=False):
    требовать(type(имя) is str and имя and '\\' not in имя and '\x00' not in имя, 'Неверное имя пути')
    значение = имя[:-1] if каталог and имя.endswith('/') else имя
    требовать(not PurePosixPath(значение).is_absolute() and all(ч not in ('', '.', '..') for ч in значение.split('/')),
              'Выход пути или неоднозначный путь')
    требовать(not any(ч in {'.git', '.build', '.swiftpm', '__pycache__', 'Зависимости', 'Источники'}
                      for ч in значение.split('/')), 'Защищённый путь')
    требовать(значение.split('/')[0] not in {'Proyekcii', 'Подузлы'}, 'Производная или историческая область')
    return значение


def в_области(имя, область):
    return any(имя == п or п.endswith('/') and имя.startswith(п) for п in область)


def точный_файл(корень, имя):
    имя_пути(имя)
    путь = Path(корень)
    требовать(путь.is_absolute() and путь == путь.resolve(strict=True), 'Нужен физический корень')
    for часть in имя.split('/'):
        требовать(путь.is_dir() and часть in {п.name for п in путь.iterdir()}, 'Неверный регистр или отсутствующий путь')
        путь /= часть
        требовать(not путь.is_symlink(), 'Символическая ссылка в пути')
    состояние = путь.stat()
    требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink == 1, 'Нужен обычный файл без жёстких ссылок')
    return путь


def проверить_коллизии(имена):
    ключи = set()
    for имя in имена:
        ключ = unicodedata.normalize('NFC', имя).casefold()
        требовать(ключ not in ключи, 'Коллизия пути exact/Unicode/casefold')
        ключи.add(ключ)


def проверить_вход(вход):
    поля(вход, {'схема', 'принимающий', 'источник', 'индекс_sha256', 'область', 'карта_sha256', 'контур'})
    требовать(вход['схема'] == 'fum.вход-русификации.1', 'Неизвестная схема входа')
    for имя in ('принимающий', 'источник'):
        проверить_хэш(вход[имя], 40)
        требовать(вход[имя] != '0' * 40, 'Нулевой OID не обозначает коммит')
    for имя in ('индекс_sha256', 'карта_sha256'):
        проверить_хэш(вход[имя])
    область = вход['область']
    требовать(type(область) is list and область and all(type(п) is str for п in область), 'Нужна конечная область строк')
    требовать(len(область) == len(set(область)), 'Повторная область')
    for имя in область:
        имя_пути(имя, каталог=True)
    проверить_коллизии([п.rstrip('/') for п in область])
    поля(вход['контур'], {'ревизия', 'хэш_исполнителя', 'файлы'})
    проверить_хэш(вход['контур']['ревизия'], 40)
    проверить_хэш(вход['контур']['хэш_исполнителя'])
    требовать(type(вход['контур']['файлы']) is list and вход['контур']['файлы'], 'Нет состава проверочного контура')
    for запись in вход['контур']['файлы']:
        поля(запись, {'путь', 'sha256'})
        имя_пути(запись['путь'])
        проверить_хэш(запись['sha256'])
    проверить_коллизии([п['путь'] for п in вход['контур']['файлы']])
    return вход


def проверить_карту(карта):
    поля(карта, {'схема', 'происхождение', 'подтверждения', 'пакеты', 'исключения'})
    требовать(карта['схема'] == 'fum.карта-русификации.1' and type(карта['происхождение']) is str
              and карта['происхождение'].strip(), 'Нет подтверждённого происхождения карты')
    for имя in ('подтверждения', 'пакеты', 'исключения'):
        требовать(type(карта[имя]) is list, 'Неверный тип списка карты')
    ключи = set()
    for запись in карта['подтверждения']:
        поля(запись, {'путь', 'язык', 'вид', 'имя', 'строка', 'столбец', 'новое'})
        имя_пути(запись['путь'])
        требовать(type(запись['язык']) is str and запись['язык'] in {'python', 'swift', 'mermaid', 'cjs'}
                  and type(запись['вид']) is str and запись['вид']
                  and type(запись['имя']) is str and запись['имя'], 'Неверная идентичность объявления')
        требовать(type(запись['новое']) is str and запись['новое'].isidentifier()
                  and re.search('[А-Яа-яЁё]', запись['новое']) and not keyword.iskeyword(запись['новое'])
                  and all(ч == '_' or ч.isdecimal() or 'А' <= ч <= 'я' or ч in 'Ёё'
                          for ч in запись['новое'].removeprefix('test_')),
                  'Нужно подтверждённое русское имя')
        требовать(type(запись['строка']) is int and запись['строка'] > 0
                  and type(запись['столбец']) is int and запись['столбец'] > 0, 'Неверные координаты объявления')
        ключ = tuple(запись[п] for п in ('путь', 'язык', 'вид', 'имя', 'строка', 'столбец'))
        требовать(ключ not in ключи, 'Повторное или конфликтующее подтверждение')
        ключи.add(ключ)
    for пакет in карта['пакеты']:
        поля(пакет, {'язык', 'карта'})
        требовать(type(пакет['язык']) is str and пакет['язык'] in {'python', 'swift', 'mermaid', 'cjs'}, 'Нет поддержанного языкового контракта')
    # Исключения первой версии закрыты: внешние обязательные имена классифицирует backend.
    требовать(not карта['исключения'], 'Новые исключения требуют отдельного принятого контракта')
    return карта


def хэш_исполнителя():
    каталог = Path(__file__).parent
    имена = ('контракт_русификации.py', 'кандидат_слияния.py', 'переводчик_русификации.py',
             'транзакция_русификации.py', 'свидетельство_русификации.py', 'русифицировать-код-при-слиянии.py')
    return хэш(байты([{'путь': п, 'sha256': хэш((каталог / п).read_bytes())} for п in имена]))

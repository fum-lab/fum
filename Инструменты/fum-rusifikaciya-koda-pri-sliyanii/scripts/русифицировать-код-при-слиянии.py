#!/usr/bin/env python3
"""Кандидат L/S: план, применение, восстановление и читающее свидетельство."""
import argparse
import sys
from pathlib import Path
from контракт_русификации import Отказ, разобрать, байты
from переводчик_русификации import построить_план
from транзакция_русификации import применить, восстановить
from свидетельство_русификации import проверить


def выполнить():
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument('команда', choices=['план', 'применить', 'восстановить', 'проверить'])
    for имя in ('корень-репозитория', 'вход', 'карта'):
        разборщик.add_argument('--' + имя, required=True)
    разборщик.add_argument('--план')
    разборщик.add_argument('--состояние')
    разборщик.add_argument('--свидетельство')
    разборщик.add_argument('--фаза', choices=['после-применения', 'перед-коммитом'], default='после-применения')
    аргументы = разборщик.parse_args()
    try:
        корень = Path(аргументы.корень_репозитория)
        вход, карта = [разобрать(Path(п).read_bytes()) for п in (аргументы.вход, аргументы.карта)]
        if аргументы.команда == 'план':
            результат = построить_план(корень, вход, карта)
        else:
            if not аргументы.план:
                raise Отказ('Нужен ранее сохранённый план')
            план = разобрать(Path(аргументы.план).read_bytes())
            if аргументы.команда == 'проверить':
                if not аргументы.свидетельство:
                    raise Отказ('Нужно свидетельство ранее применённого плана')
                квитанция = разобрать(Path(аргументы.свидетельство).read_bytes())
                результат = проверить(корень, вход, карта, план, квитанция, аргументы.фаза)
            else:
                if not аргументы.состояние:
                    raise Отказ('Нужен внешний каталог транзакции')
                процедура = применить if аргументы.команда == 'применить' else восстановить
                результат = процедура(корень, вход, карта, план, Path(аргументы.состояние))
        sys.stdout.buffer.write(байты(результат))
        return 0 if результат['допуск'] else 1
    except (Отказ, OSError, UnicodeError, ValueError, KeyError, TypeError) as ошибка:
        sys.stderr.write(str(ошибка) + '\n')
        return 2


if __name__ == '__main__':
    raise SystemExit(выполнить())

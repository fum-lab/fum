def проверить_контур(корень, вход):
    контур = вход['контур']
    требовать(контур['ревизия'] == вход['принимающий'], 'Контур не закреплён принимающим HEAD')
    требовать(контур['хэш_исполнителя'] == хэш_исполнителя(), 'Исполнитель изменился')
    требовать(sorted(п['путь'] for п in контур['файлы']) == СОСТАВ, 'Неполное замыкание Python backend')
    данные = {}
    for запись in контур['файлы']:
        имя = запись['путь']
        данные[имя] = точный_файл(корень, имя).read_bytes()
        требовать(хэш(данные[имя]) == запись['sha256']
                  and данные[имя] == гит(корень, 'show', контур['ревизия'] + ':' + имя), 'Изменён принятый backend')
    return данные


@contextmanager
def загрузить_контур(корень, данные):
    # Исходники исполняются из проверенных байтов, не перечитываются загрузчиком.
    прежние = {и: sys.modules.get(и) for и in МОДУЛИ}
    готовые = {}
    штатный_импорт = builtins.__import__

    def загрузить(имя):
        if имя not in готовые:
            модуль = types.ModuleType(имя)
            модуль.__file__ = str(корень / ПЕРЕВОДЧИК / 'scripts' / МОДУЛИ[имя])
            модуль.__dict__['__builtins__'] = {**vars(builtins), '__import__': импортировать}
            готовые[имя] = sys.modules[имя] = модуль
            exec(compile(данные[ПЕРЕВОДЧИК + 'scripts/' + МОДУЛИ[имя]], модуль.__file__, 'exec'), модуль.__dict__)
        return готовые[имя]

    def импортировать(имя, globals=None, locals=None, fromlist=(), level=0):
        if имя in МОДУЛИ and not level:
            return загрузить(имя)
        return штатный_импорт(имя, globals, locals, fromlist, level)

    try:
        yield загрузить('переводчик_объявлений'), загрузить('пакет_перевода_python')
    finally:
        for имя, прежний in прежние.items():
            if прежний is None:
                sys.modules.pop(имя, None)
            else:
                sys.modules[имя] = прежний


def объявления(модуль, текст, имя):
    дерево = ast.parse(текст, filename=имя)
    требовать(not any(isinstance(у, ast.Match) or getattr(у, 'type_params', None)
                     or type(у).__name__ == 'TypeAlias' for у in ast.walk(дерево)),
              'Pattern bindings и параметры типов не покрыты принятым инвентарём')
    def покрытое_имя(значение):
        return all(not ч.isalpha() or ч.isascii() or 'А' <= ч <= 'я' or ч in 'Ёё' for ч in значение)

    for токен in tokenize.generate_tokens(io.StringIO(текст).readline):
        if токен.type == tokenize.NAME:
            требовать(покрытое_имя(токен.string),
                      'Unicode-имя не покрыто принятым инвентарём')
    # Python нормализует имена при разборе; токены могут разделить комбинируемый знак.
    for узел in ast.walk(дерево):
        for поле, значение in ast.iter_fields(узел):
            if поле in {'name', 'id', 'arg', 'attr', 'asname'} and isinstance(значение, str):
                требовать(покрытое_имя(значение), 'Нормализованное Unicode-имя не покрыто принятым инвентарём')
            if поле == 'names' and isinstance(узел, (ast.Global, ast.Nonlocal)):
                требовать(all(покрытое_имя(имя) for имя in значение),
                          'Нормализованное Unicode-имя не покрыто принятым инвентарём')
    сборщик = модуль.СборщикОбъявленийПитона(имя, дерево)
    сборщик.visit(дерево)
    return [п.словарь() for п in сборщик.объявления]


def ключ(объявление):
    return tuple(объявление[п] for п in ('путь', 'язык', 'вид', 'имя', 'строка', 'столбец'))


def новые_объявления(модуль, корень, вход, имя, текст):
    # Только неизменные строки с прежней идентичностью считаются историческими.
    прежние_пути = гит(корень, 'ls-tree', '--name-only', '-z', вход['принимающий'], '--', имя).split(b'\0')
    прежний = гит(корень, 'show', вход['принимающий'] + ':' + имя).decode('utf-8') if имя.encode() in прежние_пути else ''
    соответствия = {}
    for блок in difflib.SequenceMatcher(None, прежний.splitlines(True), текст.splitlines(True), autojunk=False).get_matching_blocks():
        соответствия.update({блок.b + и + 1: блок.a + и + 1 for и in range(блок.size)})
    def владельцы(исходник, перенос=None):
        результат = {}

        def пройти(узел, область):
            if hasattr(узел, 'lineno'):
                результат[узел.lineno, узел.col_offset + 1] = область
            if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Lambda,
                                  ast.ListComp, ast.SetComp, ast.DictComp, ast.GeneratorExp)):
                строка = перенос.get(узел.lineno) if перенос is not None else узел.lineno
                область += ((type(узел).__name__, getattr(узел, 'name', ''), строка, узел.col_offset),)
            for ребёнок in ast.iter_child_nodes(узел):
                пройти(ребёнок, область)

        пройти(ast.parse(исходник), ())
        return результат

    старые_владельцы, новые_владельцы = владельцы(прежний), владельцы(текст, соответствия)
    старые = {(п['вид'], п['имя'], п['строка'], п['столбец'], старые_владельцы.get((п['строка'], п['столбец'])))
              for п in объявления(модуль, прежний, имя)}
    return [п for п in объявления(модуль, текст, имя)
            if (п['вид'], п['имя'], соответствия.get(п['строка']), п['столбец'],
                новые_владельцы.get((п['строка'], п['столбец']))) not in старые]


class ЧитательИсходника:
    def __init__(сам, данные):
        сам.данные = данные

    def read_bytes(сам):
        return сам.данные


def построить_план(корень, вход, карта, измерения=None, *, из_индекса=False, сохранённый_индекс=None):
    начало = time.perf_counter_ns()
    корень = Path(корень)
    текущий = прочитать_кандидат(корень, вход, итоговый_индекс=сохранённый_индекс is not None)
    снимок = текущий
    if сохранённый_индекс is not None:
        требовать(из_индекса, 'Сохранённый индекс только для содержательной сверки')
        проверить_снимок_индекса(сохранённый_индекс, вход['индекс_sha256'])
        прежние = {}
        for запись in гит(корень, 'ls-tree', '-r', '-z', вход['принимающий']).split(b'\0'):
            if запись:
                свойства, имя = запись.split(b'\t', 1)
                режим, _, объект = свойства.decode().split()
                прежние[имя.decode('utf-8')] = (режим, объект)
        кандидаты = {п['путь']: (п['режим'], п['blob']) for п in сохранённый_индекс['записи']}
        изменённые = sorted(п for п in set(прежние) | set(кандидаты) if прежние.get(п) != кандидаты.get(п))
        снимок = {'индекс': сохранённый_индекс, 'изменённые': изменённые}
    проверить_карту(карта)
    требовать(хэш(байты(карта)) == вход['карта_sha256'], 'Карта изменилась')
    после_кандидата = time.perf_counter_ns()
    if измерения is not None:
        измерения.append({'стадия': 'кандидат_и_входы', 'длительность_наносекунды': после_кандидата - начало})
    данные = проверить_контур(корень, вход)
    требовать(all(п['язык'] == 'python' for п in карта['пакеты']),
              'Swift требует принятого V2; Mermaid/CJS не приняты в этом срезе')
    пакеты = карта['пакеты']
    требовать(len(пакеты) <= 1, 'Повторный языковой пакет')
    манифест = пакеты[0]['карта'] if пакеты else {'схема': 'fum.пакет-перевода-python.1', 'файлы': []}
    поля(манифест, {'схема', 'файлы'})
    требовать(type(манифест['файлы']) is list, 'Неверный состав пакета')
    записи = манифест['файлы']
    for запись in записи:
        требовать(type(запись) is dict and {'путь', 'хэш', 'переводы', 'области', 'связи', 'передачи'} <= set(запись)
                  and not set(запись) - {'путь', 'хэш', 'переводы', 'области', 'связи', 'передачи', 'имена_областей', 'код', 'исполнения', 'внешние_вызовы'},
                  'Неизвестные поля файла пакета')
        требовать(type(запись['путь']) is str and type(запись['переводы']) is dict, 'Неверный путь или карта пакета')
    имена = [п['путь'] for п in записи]
    проверить_коллизии(имена)
    требовать(all(в_области(п, вход['область']) and п.endswith('.py') for п in имена), 'Пакет вне области Python')
    def прочитать(имя):
        if not из_индекса:
            return исходные_байты(корень, снимок, имя)
        точный_файл(корень, имя)
        записи_индекса = [п for п in снимок['индекс']['записи'] if п['путь'] == имя]
        требовать(len(записи_индекса) == 1 and записи_индекса[0]['режим'] in {'100644', '100755'}, 'Нет первоначального исходника')
        return гит(корень, 'cat-file', 'blob', записи_индекса[0]['blob'])

    исходники = {п: прочитать(п) for п in имена}
    после_исходников = time.perf_counter_ns()
    if измерения is not None:
        измерения.append({'стадия': 'контур_и_исходники', 'длительность_наносекунды': после_исходников - после_кандидата})
    подтверждения = {ключ(п): п['новое'] for п in карта['подтверждения']}
    новые = []
    изменения = []
    with загрузить_контур(корень, данные) as (объявитель, переводчик):
        if из_индекса:
            # Только проверенный локальный модуль получает байты исходного stage0.
            переводчик.точный_файл = lambda корень, имя: ЧитательИсходника(исходники[имя])
        for имя in снимок['изменённые']:
            if not в_области(имя, вход['область']):
                continue
            требовать(имя.endswith('.py'), 'Нет принятого backend для изменённого собственного формата')
            if имя not in исходники:
                исходники[имя] = прочитать(имя)
            текст = исходники[имя].decode('utf-8')
            новые.extend(новые_объявления(объявитель, корень, вход, имя, текст))
        запросы = [п for п in новые if ключ(п) not in подтверждения]
        требовать(set(подтверждения) <= {ключ(п) for п in новые}, 'Подтверждение не принадлежит новому объявлению')
        for запись in записи:
            for старое, новое in запись['переводы'].items():
                выбранные = [п for п in новые if п['путь'] == запись['путь'] and п['имя'] == старое]
                if not запросы:
                    требовать(выбранные and all(подтверждения.get(ключ(п)) == новое for п in выбранные),
                              'Слово пакета не подтверждено конкретными объявлениями')
                # До принятия адресного выбора областей запрещаем захват исторического одноимённого объявления.
                все = объявления(объявитель, исходники[запись['путь']].decode('utf-8'), запись['путь'])
                требовать(all(п in выбранные for п in все if п['имя'] == старое), 'Карта захватывает историческую привязку')
        if not запросы:
            до_перевода = time.perf_counter_ns()
            if измерения is not None:
                измерения.append({'стадия': 'объявления_и_подтверждения', 'длительность_наносекунды': до_перевода - после_исходников})
            try:
                изменения = переводчик.подготовить(корень, манифест, измерения)
            except (ValueError, SyntaxError, UnicodeError, KeyError, TypeError) as ошибка:
                raise Отказ('Backend отказал: ' + str(ошибка)) from ошибка
            покрытые = {(п['путь'], с, н) for п in изменения for с, н in п['переводы'].items()}
            требовать(all((п['путь'], п['имя'], подтверждения[ключ(п)]) in покрытые for п in новые), 'Нет перевода подтверждённого объявления')
    файлы = []
    for изменение in изменения:
        имя = изменение['путь']
        запись = next(п for п in снимок['индекс']['записи'] if п['путь'] == имя)
        файлы.append({'путь': имя, 'до': изменение['до'], 'после': изменение['после'],
                      'режим': запись['режим'], 'режим_файла': (корень / имя).stat().st_mode & 0o777,
                      'результат': изменение['текст'], 'связи': изменение['связи'], 'привязки': изменение['привязки'],
                      'координаты': 'индексы Unicode; связи в исходном тексте, привязки после связей',
                      'различия': ''.join(difflib.unified_diff(исходники[имя].decode().splitlines(True),
                                           изменение['текст'].splitlines(True), fromfile=имя, tofile=имя))})
    требовать(прочитать_кандидат(корень, вход, итоговый_индекс=сохранённый_индекс is not None) == текущий
              and проверить_контур(корень, вход) == данные,
              'Кандидат или контур изменился во время плана')
    for имя, исходник in исходники.items():
        требовать(прочитать(имя) == исходник, 'Поздний дрейф исходника')
    if измерения is not None:
        измерения.append({'стадия': 'весь_план', 'длительность_наносекунды': time.perf_counter_ns() - начало})
    return {'схема': 'fum.план-русификации.1', 'допуск': not запросы, 'вход': разобрать(байты(вход)),
            'хэш_карты': хэш(байты(карта)), 'запросы': запросы, 'исключения': [],
            'индекс': снимок['индекс'], 'файлы': sorted(файлы, key=lambda п: п['путь']),
            'исходники': [{'путь': п, 'хэш': хэш(б), 'режим_файла': (корень / п).stat().st_mode & 0o777}
                         for п, б in sorted(исходники.items())]}

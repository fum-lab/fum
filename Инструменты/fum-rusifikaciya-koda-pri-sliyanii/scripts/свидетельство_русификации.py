"""Читающий допуск точных рабочих байтов и всего итогового индекса."""
import hashlib
from pathlib import Path
from контракт_русификации import байты, хэш, требовать, точный_файл, поля
from кандидат_слияния import гит, прочитать_кандидат
from переводчик_русификации import проверить_контур, построить_план


def объект_байтов(данные):
    # Git blob OID без hash-object и записи объектов.
    return hashlib.sha1(b'blob ' + str(len(данные)).encode() + b'\0' + данные).hexdigest()


def снять_свидетельство(корень, вход, карта, план, фаза):
    требовать(фаза in {'после-применения', 'перед-коммитом'}, 'Неизвестная фаза свидетельства')
    требовать(план['схема'] == 'fum.план-русификации.1' and план['допуск'] is True
              and план['вход'] == вход and план['хэш_карты'] == хэш(байты(карта)), 'Свидетельство не связано с входом')
    проверить_контур(Path(корень), вход)
    снимок = прочитать_кандидат(Path(корень), вход, итоговый_индекс=фаза == 'перед-коммитом')
    требовать(план == построить_план(Path(корень), вход, карта, из_индекса=True, сохранённый_индекс=план['индекс']),
              'Содержательный исходный план не воспроизводится')
    ожидаемые = {п['путь']: dict(п) for п in план['индекс']['записи']}
    требовать(план['индекс']['sha256'] == вход['индекс_sha256'], 'Иной первоначальный индекс')
    изменяемые = {п['путь'] for п in план['файлы']}
    for исходник in план['исходники']:
        if исходник['путь'] in изменяемые:
            continue
        путь = точный_файл(Path(корень), исходник['путь'])
        требовать(хэш(путь.read_bytes()) == исходник['хэш'] and путь.stat().st_mode & 0o777 == исходник['режим_файла'],
                  'Дрейф рассмотренного исходника')
    for файл in план['файлы']:
        путь = точный_файл(Path(корень), файл['путь'])
        данные = путь.read_bytes()
        требовать(данные == файл['результат'].encode('utf-8') and хэш(данные) == файл['после']
                  and путь.stat().st_mode & 0o777 == файл['режим_файла'], 'Дрейф итоговых байтов или режима')
        if фаза == 'перед-коммитом':
            ожидаемые[файл['путь']]['blob'] = объект_байтов(данные)
            ожидаемые[файл['путь']]['режим'] = файл['режим']
    требовать(sorted(ожидаемые.values(), key=lambda п: п['путь']) ==
              sorted(снимок['индекс']['записи'], key=lambda п: п['путь']), 'Индекс не равен полному ожидаемому составу')
    требовать(снимок == прочитать_кандидат(Path(корень), вход, итоговый_индекс=фаза == 'перед-коммитом'),
              'Кандидат изменился при сверке свидетельства')
    return {'схема': 'fum.свидетельство-русификации.1', 'допуск': True, 'фаза': фаза,
            'принимающий': вход['принимающий'], 'источник': вход['источник'],
            'родители': [вход['принимающий'], вход['источник']], 'хэш_плана': хэш(байты(план)),
            'хэш_итогового_индекса': снимок['индекс']['sha256'],
            'файлы': [{п: ф[п] for п in ('путь', 'после', 'режим')} for ф in план['файлы']]}


def проверить(корень, вход, карта, план, квитанция, фаза):
    поля(квитанция, {'схема', 'допуск', 'фаза', 'принимающий', 'источник', 'родители', 'хэш_плана', 'хэш_итогового_индекса', 'файлы'})
    ожидаемая = {'схема': 'fum.свидетельство-русификации.1', 'допуск': True, 'фаза': 'после-применения',
                 'принимающий': вход['принимающий'], 'источник': вход['источник'],
                 'родители': [вход['принимающий'], вход['источник']], 'хэш_плана': хэш(байты(план)),
                 'хэш_итогового_индекса': вход['индекс_sha256'],
                 'файлы': [{п: ф[п] for п in ('путь', 'после', 'режим')} for ф in план['файлы']]}
    требовать(квитанция == ожидаемая, 'Нет точного исходного свидетельства применения')
    return снять_свидетельство(корень, вход, карта, план, фаза)

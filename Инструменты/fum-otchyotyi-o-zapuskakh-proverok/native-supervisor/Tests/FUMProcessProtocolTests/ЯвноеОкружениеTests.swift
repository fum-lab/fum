import Testing
@testable import FUMProcessProtocol

@Test func окружениеСохраняетБайтыИОтвергаетНеоднозначность() throws {
    #expect(ЯвноеОкружение([])?.записи == [])
    let вход: [UInt8] = [65, 61, 0, 66, 61, 255, 61, 0]
    #expect(ЯвноеОкружение(вход)?.записи == [[65, 61], [66, 61, 255, 61]])
    for неверный: [UInt8] in [[0], [61, 65, 0], [65, 0], [65, 61], [65, 61, 0, 0], [65, 61, 0, 65, 61, 49, 0]] {
        #expect(ЯвноеОкружение(неверный) == nil)
    }
    let край = [UInt8](repeating: 65, count: 65_534) + [61, 0]
    #expect(ЯвноеОкружение(край) != nil)
    #expect(ЯвноеОкружение(край + [0]) == nil)
    let много = (0..<256).flatMap { Array("K\($0)=\0".utf8) }
    #expect(ЯвноеОкружение(много)?.записи.count == 256)
    #expect(ЯвноеОкружение(много + Array("LAST=\0".utf8)) == nil)
}

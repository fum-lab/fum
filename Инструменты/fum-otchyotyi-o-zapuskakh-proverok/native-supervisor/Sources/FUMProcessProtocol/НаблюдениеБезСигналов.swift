import Darwin

public enum ИтогОпросаДочернегоПроцесса: Equatable, Sendable {
    case нетРезультата
    case собран(pid: Int32, сыройСтатус: Int32)
    case неизвестно(errno: Int32)
}

/// Только единственный владелец непосредственного child вправе вызывать опрос.
/// Повтор последнего результата не повторяет waitpid; сигналы не отправляются.
public final class НаблюдениеДочернегоПроцесса {
    public let pid: Int32
    private var окончательный: ИтогОпросаДочернегоПроцесса?

    public init?(pid: Int32) {
        guard pid > 1, pid != getpid() else { return nil }
        self.pid = pid
    }

    public func опросить() -> ИтогОпросаДочернегоПроцесса {
        if let окончательный { return окончательный }
        var сырой: Int32 = 0
        let результат = waitpid(pid, &сырой, WNOHANG)
        if результат == 0 || (результат == -1 && errno == EINTR) { return .нетРезультата }
        let итог: ИтогОпросаДочернегоПроцесса
        if результат == pid {
            итог = .собран(pid: pid, сыройСтатус: сырой)
        } else {
            итог = .неизвестно(errno: результат == -1 ? errno : EINVAL)
        }
        окончательный = итог
        return итог
    }
}

public enum ПричинаНеизвестногоНаблюдения: Equatable, Sendable {
    case срок
    case часы
    case внешняя
    case wait(errno: Int32)
}

public enum ИсходОграниченногоНаблюдения: Equatable, Sendable {
    case нетРезультата
    case собран(pid: Int32, сыройСтатус: Int32)
    case неизвестно(ПричинаНеизвестногоНаблюдения)
}

/// Единоличное владение child предоставляется вызывающим. Срок ограничивает
/// момент наблюдения, но не устанавливает время завершения процесса.
/// После UNKNOWN добор сохраняет исходную неопределённость и не посылает сигнал.
public final class ОграниченноеНаблюдениеБезСигналов {
    private let наблюдение: НаблюдениеДочернегоПроцесса
    private let край: Int64
    private var последнееВремя: Int64
    public private(set) var итог: ИсходОграниченногоНаблюдения?

    public init?(pid: Int32, начало: Int64, край: Int64) {
        guard начало >= 0, край > начало, let наблюдение = НаблюдениеДочернегоПроцесса(pid: pid) else { return nil }
        self.наблюдение = наблюдение
        self.край = край
        self.последнееВремя = начало
    }

    public func опросить(часы: () -> Int64?) -> ИсходОграниченногоНаблюдения {
        if let итог { return итог }
        guard let до = часы(), до >= последнееВремя else { return завершить(.неизвестно(.часы)) }
        последнееВремя = до
        guard до < край else { return завершить(.неизвестно(.срок)) }
        let наблюдаемый = наблюдение.опросить()
        guard let после = часы(), после >= до else { return завершить(.неизвестно(.часы)) }
        последнееВремя = после
        guard после < край else { return завершить(.неизвестно(.срок)) }
        switch наблюдаемый {
        case .нетРезультата: return .нетРезультата
        case let .собран(pid, статус): return завершить(.собран(pid: pid, сыройСтатус: статус))
        case let .неизвестно(ошибка): return завершить(.неизвестно(.wait(errno: ошибка)))
        }
    }

    public func добратьПослеНеизвестного() -> ИтогОпросаДочернегоПроцесса? {
        guard case .неизвестно = итог else { return nil }
        return наблюдение.опросить()
    }

    public func отметитьВнешнююНеопределённость() -> ИсходОграниченногоНаблюдения {
        if let итог { return итог }
        return завершить(.неизвестно(.внешняя))
    }

    private func завершить(_ результат: ИсходОграниченногоНаблюдения) -> ИсходОграниченногоНаблюдения {
        итог = результат
        return результат
    }
}

/// Монотонные миллисекунды Darwin; при ошибке или переполнении — отсутствие времени.
public func монотонныеМиллисекундыНаблюдателя() -> Int64? {
    var время = timespec()
    guard clock_gettime(CLOCK_UPTIME_RAW, &время) == 0, время.tv_sec >= 0,
          (0..<1_000_000_000).contains(время.tv_nsec) else { return nil }
    let (секунды, переполнение) = Int64(время.tv_sec).multipliedReportingOverflow(by: 1000)
    let (итог, переполнениеСуммы) = секунды.addingReportingOverflow(Int64(время.tv_nsec) / 1_000_000)
    return переполнение || переполнениеСуммы ? nil : итог
}

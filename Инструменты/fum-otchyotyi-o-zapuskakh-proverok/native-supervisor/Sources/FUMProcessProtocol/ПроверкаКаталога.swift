/// Проверяет только открытый объект в момент вызова. Путь, предки и custody не подтверждаются.
public func подтвердитьОткрытыйКаталог(_ опора: ОпораЗаимствованногоКаталога) -> Bool {
    guard getuid() == geteuid(), опора.владелец == getuid() else { return false }
    let флаги = fcntl(опора.дескриптор, F_GETFL)
    let флагиДескриптора = fcntl(опора.дескриптор, F_GETFD)
    guard флаги >= 0, флаги & O_ACCMODE == O_RDONLY, флагиДескриптора >= 0 else { return false }
    var метка = stat()
    guard fstat(опора.дескриптор, &метка) == 0 else { return false }
    return метка.st_mode & UInt16(S_IFMT) == UInt16(S_IFDIR) &&
        метка.st_mode & 0o7777 == опора.режим && метка.st_uid == опора.владелец &&
        UInt64(exactly: метка.st_dev) == опора.устройство && метка.st_ino == опора.инод
}

/// Проверяет типы и заявленные метки в одной точке до передачи; custody не устанавливает.
public func подтвердитьОпорыСинтетическогоПомощника(
    _ номера: ДескрипторыСинтетическогоПомощника,
    корень: ОпораЗаимствованногоКаталога,
    замок: ОпораЗаимствованногоКаталога,
    квитанции: ОпораЗаимствованногоКаталога
) -> Bool {
    let каталоги = [корень, замок, квитанции]
    guard корень.дескриптор == номера.корень, замок.дескриптор == номера.замок,
          квитанции.дескриптор == номера.квитанции,
          корень.область == .рабочееДерево, замок.область == .приватныеКвитанции,
          квитанции.область == .приватныеКвитанции,
          каталоги.allSatisfy({ $0.режим == 0o700 && подтвердитьОткрытыйКаталог($0) }),
          Set(каталоги.map { "\($0.устройство):\($0.инод)" }).count == 3 else { return false }
    let все = [номера.канал, номера.корень, номера.замок, номера.квитанции]
    guard все.allSatisfy({ fd in
        let флаги = fcntl(fd, F_GETFD)
        return флаги >= 0 && флаги & FD_CLOEXEC != 0
    }) else { return false }
    let режим = fcntl(номера.канал, F_GETFL)
    var канал = stat()
    return режим >= 0 && режим & O_ACCMODE == O_RDONLY && fstat(номера.канал, &канал) == 0 &&
        канал.st_mode & UInt16(S_IFMT) == UInt16(S_IFIFO) && канал.st_uid == getuid()
}

/// Добавляет только четыре согласованные опоры; при false вызывающий уничтожает actions.
/// POSIX_SPAWN_CLOEXEC_DEFAULT и допустимость цели задаются вызывающим отдельно.
public func подготовитьПередачуОпорПомощника(
    _ номера: ДескрипторыСинтетическогоПомощника,
    корень: ОпораЗаимствованногоКаталога,
    замок: ОпораЗаимствованногоКаталога,
    квитанции: ОпораЗаимствованногоКаталога,
    действия: inout posix_spawn_file_actions_t?
) -> Bool {
    guard действия != nil,
          подтвердитьОпорыСинтетическогоПомощника(номера, корень: корень, замок: замок, квитанции: квитанции)
    else { return false }
    for fd in [номера.канал, номера.корень, номера.замок, номера.квитанции] {
        guard posix_spawn_file_actions_addinherit_np(&действия, fd) == 0 else { return false }
    }
    return подтвердитьОпорыСинтетическогоПомощника(номера, корень: корень, замок: замок, квитанции: квитанции)
}

/// Две однонаправленные опоры; происхождение пары и peer проверяются отдельно.
public func подтвердитьДуплексныеОпорыПомощника(
    _ опоры: ДуплексныеОпорыПомощника, корень: ОпораЗаимствованногоКаталога,
    замок: ОпораЗаимствованногоКаталога, квитанции: ОпораЗаимствованногоКаталога
) -> Bool {
    guard подтвердитьОпорыСинтетическогоПомощника(опоры.вход, корень: корень, замок: замок, квитанции: квитанции)
    else { return false }
    let флаги = fcntl(опоры.ответ, F_GETFL)
    let fdФлаги = fcntl(опоры.ответ, F_GETFD)
    var канал = stat()
    return флаги >= 0 && флаги & O_ACCMODE == O_WRONLY && fdФлаги >= 0 && fdФлаги & FD_CLOEXEC != 0 &&
        fstat(опоры.ответ, &канал) == 0 && канал.st_mode & UInt16(S_IFMT) == UInt16(S_IFIFO) && канал.st_uid == getuid()
}

/// При false actions не используются и уничтожаются вызывающим.
public func подготовитьДуплекснуюПередачуПомощника(
    _ опоры: ДуплексныеОпорыПомощника, корень: ОпораЗаимствованногоКаталога,
    замок: ОпораЗаимствованногоКаталога, квитанции: ОпораЗаимствованногоКаталога,
    действия: inout posix_spawn_file_actions_t?
) -> Bool {
    guard подтвердитьДуплексныеОпорыПомощника(опоры, корень: корень, замок: замок, квитанции: квитанции),
          подготовитьПередачуОпорПомощника(опоры.вход, корень: корень, замок: замок,
                                         квитанции: квитанции, действия: &действия),
          posix_spawn_file_actions_addinherit_np(&действия, опоры.ответ) == 0 else { return false }
    return подтвердитьДуплексныеОпорыПомощника(опоры, корень: корень, замок: замок, квитанции: квитанции)
}

/// Точечная проверка семи ролей; не подтверждает путь, issuer или custody.
public func подтвердитьОпорыМостаПомощника(
    _ опоры: ОпорыМостаПомощника, корень: ОпораЗаимствованногоКаталога,
    замок: ОпораЗаимствованногоКаталога, квитанции: ОпораЗаимствованногоКаталога,
    сессия: ОпораЗаимствованногоКаталога, мост: ОпораЗаимствованногоКаталога
) -> Bool {
    let каталоги = [корень, замок, квитанции, сессия, мост]
    guard подтвердитьДуплексныеОпорыПомощника(опоры.дуплекс, корень: корень, замок: замок,
                                            квитанции: квитанции),
          сессия.дескриптор == опоры.сессия, мост.дескриптор == опоры.мост,
          сессия.область == .приватныеКвитанции, мост.область == .приватныеКвитанции,
          каталоги.allSatisfy({ $0.режим == 0o700 && подтвердитьОткрытыйКаталог($0) }),
          Set(каталоги.map { "\($0.устройство):\($0.инод)" }).count == 5 else { return false }
    return [опоры.сессия, опоры.мост].allSatisfy { fd in
        let flags = fcntl(fd, F_GETFD)
        return flags >= 0 && flags & FD_CLOEXEC != 0
    }
}

/// При false вызывающий уничтожает actions и не запускает цель.
public func подготовитьПередачуМостаПомощника(
    _ опоры: ОпорыМостаПомощника, корень: ОпораЗаимствованногоКаталога,
    замок: ОпораЗаимствованногоКаталога, квитанции: ОпораЗаимствованногоКаталога,
    сессия: ОпораЗаимствованногоКаталога, мост: ОпораЗаимствованногоКаталога,
    действия: inout posix_spawn_file_actions_t?
) -> Bool {
    func сверить() -> Bool {
        подтвердитьОпорыМостаПомощника(опоры, корень: корень, замок: замок, квитанции: квитанции,
                                      сессия: сессия, мост: мост)
    }
    guard сверить(), подготовитьДуплекснуюПередачуПомощника(
        опоры.дуплекс, корень: корень, замок: замок, квитанции: квитанции, действия: &действия),
        posix_spawn_file_actions_addinherit_np(&действия, опоры.сессия) == 0,
        posix_spawn_file_actions_addinherit_np(&действия, опоры.мост) == 0 else { return false }
    return сверить()
}

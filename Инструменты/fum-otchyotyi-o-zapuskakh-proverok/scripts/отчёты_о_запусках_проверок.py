def профиль_записи(запись: dict[str, object]) -> dict[str, object] | None:
    if запись.get("схема") != СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА:
        return None
    профиль = запись.get("профиль_проверки")
    return профиль if isinstance(профиль, dict) else None


def история_схем_несовместима(записи: Sequence[dict[str, object]]) -> bool:
    первый_профилированный_порядок = min(
        (
            int(запись["порядок"])
            for запись in записи
            if запись.get("схема") == СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА
        ),
        default=None,
    )
    return bool(
        первый_профилированный_порядок is not None
        and (
            any(
                запись.get("схема") == СХЕМА_ЗАПУСКА_С_НАБЛЮДЕНИЯМИ
                for запись in записи
            )
            or any(
                int(запись["порядок"])
                > первый_профилированный_порядок
                and запись.get("схема") != СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА
                for запись in записи
            )
        )
    )


def вычислить_хэш_префикса_раундов(
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
) -> str:
    """v4: числовой порядок, имя и сырые байты; длины — беззнаковые 64-битные big-endian."""
    хэш = hashlib.sha256()
    добавить_часть_отпечатка(хэш, "схема", "fum.префикс-приёмочных-раундов.1".encode("utf-8"))
    for путь, _, байты in sorted(записи, key=lambda элемент: int(элемент[1]["порядок"])):
        добавить_часть_отпечатка(хэш, путь.name, байты)
    return f"sha256:{хэш.hexdigest()}"


def проверить_основу_истории_раундов(
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
) -> list[tuple[Path, dict[str, object], bytes]]:
    if not записи:
        raise ОшибкаОтчёта("история раундов пуста")
    if not isinstance(записи[0][1], dict):
        raise ОшибкаОтчёта("история требует словарь записи")
    сессия = проверить_аналитический_ключ(записи[0][1].get("сессия"), "сессия раундов")
    части_сессии = PurePosixPath(сессия).parts
    if len(части_сессии) != 3 or части_сессии[0] != КАТАЛОГ_ЖУРНАЛА or части_сессии[-1] != ИМЯ_ЗАПРОСА:
        raise ОшибкаОтчёта("сессия раундов должна указывать на запрос в Журнале")
    for путь, значение, байты in записи:
        проверить_запись(значение, путь.name, сессия)
        try:
            прочитанное = json.loads(байты.decode("utf-8"))
        except (UnicodeError, json.JSONDecodeError) as ошибка:
            raise ОшибкаОтчёта("не удалось разобрать сохранённые байты раунда") from ошибка
        проверить_запись(прочитанное, путь.name, сессия)
        if прочитанное != значение:
            raise ОшибкаОтчёта("разобранная запись не совпадает с сохранёнными байтами")
    упорядоченные = sorted(записи, key=lambda элемент: int(элемент[1]["порядок"]))
    порядки = [элемент[1]["порядок"] for элемент in упорядоченные]
    идентификаторы = [элемент[1]["идентификатор"] for элемент in упорядоченные]
    if len(set(порядки)) != len(порядки) or len(set(идентификаторы)) != len(идентификаторы):
        raise ОшибкаОтчёта("история раундов содержит повтор порядка или UUID")
    return упорядоченные


def проверить_историю_раундов(
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
) -> list[tuple[Path, dict[str, object], bytes]]:
    """Проверяет сохранённые данные без обращения к текущему Git или контрактным файлам."""
    упорядоченные = проверить_основу_истории_раундов(записи)
    граница = next(
        (номер for номер, (_, запись, _) in enumerate(упорядоченные)
         if запись["схема"] == СХЕМА_ЗАПУСКА_С_РАУНДАМИ),
        None,
    )
    if граница is None:
        raise ОшибкаОтчёта("история не содержит приёмочных раундов v4")
    префикс = упорядоченные[:граница]
    новые = упорядоченные[граница:]
    if any(запись["схема"] != СХЕМА_ЗАПУСКА_С_РАУНДАМИ for _, запись, _ in новые):
        raise ОшибкаОтчёта("старую схему нельзя добавлять после первого раунда v4")
    if any(запись["состояние"] != "завершён" for _, запись, _ in префикс):
        raise ОшибкаОтчёта("миграция запрещена при активном историческом запуске")
    if (
        any(запись["схема"] == СХЕМА_ЗАПУСКА_С_НАБЛЮДЕНИЯМИ for _, запись, _ in префикс)
        or история_схем_несовместима([запись for _, запись, _ in префикс])
    ):
        raise ОшибкаОтчёта("исторический префикс содержит несовместимые схемы")
    первый = новые[0][1]
    переход = первый["переход_схемы"]
    if префикс:
        if переход is None:
            raise ОшибкаОтчёта("первый v4 после старых записей требует переход")
        if (
            переход["последний_порядок"] != префикс[-1][1]["порядок"]
            or переход["число_записей"] != len(префикс)
            or переход["хэш_префикса"] != вычислить_хэш_префикса_раундов(префикс)
        ):
            raise ОшибкаОтчёта("исторический префикс не совпадает с границей перехода")
        начало = int(префикс[-1][1]["порядок"]) + 1
    else:
        if переход is not None:
            raise ОшибкаОтчёта("чистая история v4 не объявляет переход")
        начало = 1
    if [запись["порядок"] for _, запись, _ in новые] != list(range(начало, начало + len(новые))):
        raise ОшибкаОтчёта("новые раунды должны продолжать порядок без пропусков")
    if any(запись["переход_схемы"] is not None for _, запись, _ in новые[1:]):
        raise ОшибкаОтчёта("переход схемы допускается только в первом v4")
    return новые




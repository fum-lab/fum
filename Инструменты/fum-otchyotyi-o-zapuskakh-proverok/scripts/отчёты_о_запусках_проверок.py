def канонические_машинные_байты(значение: object) -> bytes:
    return (
        json.dumps(
            значение,
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
        )
        + "\n"
    ).encode("utf-8")


def хэш_содержимого(байты: bytes) -> str:
    return hashlib.sha256(байты).hexdigest()


def проверить_обычный_путь(путь: Path, назначение: str) -> None:
    if путь.is_symlink() or not путь.is_file():
        raise ОшибкаОтчёта(f"{назначение} должен быть обычным файлом: {путь}")


def проверить_компоненты_без_ссылок(корень: Path, путь: Path) -> None:
    текущий = корень
    for часть in путь.relative_to(корень).parts:
        текущий = текущий / часть
        if текущий.is_symlink():
            raise ОшибкаОтчёта(
                f"символическая ссылка в управляемом пути запрещена: {текущий}"
            )


def разрешить_сессию(
    корень_репозитория: str | Path,
    запрос: str | Path,
) -> tuple[Path, Path, Path, Path, str]:
    корень = Path(корень_репозитория).resolve()
    if not корень.is_dir():
        raise ОшибкаОтчёта(f"корень репозитория не является каталогом: {корень}")

    исходный_путь = Path(запрос)
    лексический_путь = Path(
        os.path.abspath(
            исходный_путь
            if исходный_путь.is_absolute()
            else корень / исходный_путь
        )
    )
    try:
        лексический_относительный = лексический_путь.relative_to(корень)
    except ValueError as ошибка:
        raise ОшибкаОтчёта("путь запроса вышел за корень репозитория") from ошибка
    if (
        len(лексический_относительный.parts) != 3
        or лексический_относительный.parts[0] != КАТАЛОГ_ЖУРНАЛА
        or лексический_относительный.name != ИМЯ_ЗАПРОСА
    ):
        raise ОшибкаОтчёта(
            "путь запроса должен иметь вид Журнал/<stem>/запрос.md"
        )
    проверить_компоненты_без_ссылок(корень, лексический_путь)

    путь_запроса = лексический_путь.resolve()
    try:
        относительный = путь_запроса.relative_to(корень)
    except ValueError as ошибка:
        raise ОшибкаОтчёта("путь запроса вышел за корень репозитория") from ошибка
    if (
        len(относительный.parts) != 3
        or относительный.parts[0] != КАТАЛОГ_ЖУРНАЛА
        or относительный.name != ИМЯ_ЗАПРОСА
    ):
        raise ОшибкаОтчёта(
            "путь запроса должен иметь вид Журнал/<stem>/запрос.md"
        )
    проверить_компоненты_без_ссылок(корень, путь_запроса)
    проверить_обычный_путь(путь_запроса, "запрос")

    путь_отчёта = путь_запроса.parent / ИМЯ_ОТЧЁТА
    проверить_компоненты_без_ссылок(корень, путь_отчёта)
    проверить_обычный_путь(путь_отчёта, "отчёт")
    каталог_запусков = путь_запроса.parent / ОТНОСИТЕЛЬНЫЙ_КАТАЛОГ_ЗАПУСКОВ
    проверить_компоненты_без_ссылок(корень, каталог_запусков)
    return (
        корень,
        путь_запроса,
        путь_отчёта,
        каталог_запусков,
        относительный.as_posix(),
    )


@contextlib.contextmanager
def межпроцессная_блокировка(корень: Path, сессия: str) -> Iterator[None]:
    ключ = хэш_содержимого(f"{корень}\0{сессия}".encode("utf-8"))
    путь = Path(tempfile.gettempdir()) / f"fum-check-runs-{ключ}.lock"
    дескриптор = os.open(путь, os.O_CREAT | os.O_RDWR, 0o600)
    try:
        fcntl.flock(дескриптор, fcntl.LOCK_EX)
        yield
    finally:
        fcntl.flock(дескриптор, fcntl.LOCK_UN)
        os.close(дескриптор)


def синхронизировать_каталог(каталог: Path) -> None:
    дескриптор = os.open(каталог, os.O_RDONLY)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def атомарно_записать_байты(путь: Path, байты: bytes) -> None:
    путь.parent.mkdir(parents=True, exist_ok=True)
    if путь.parent.is_symlink():
        raise ОшибкаОтчёта(
            f"символическая ссылка вместо каталога записи запрещена: {путь.parent}"
        )
    временный = путь.parent / f".{путь.name}.{uuid.uuid4()}.tmp"
    режим = 0o644
    if путь.exists() and not путь.is_symlink():
        режим = путь.stat().st_mode & 0o777
    дескриптор: int | None = None
    try:
        дескриптор = os.open(
            временный,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL,
            режим,
        )
        with os.fdopen(дескриптор, "wb") as поток:
            дескриптор = None
            поток.write(байты)
            поток.flush()
            os.fsync(поток.fileno())
        os.replace(временный, путь)
        синхронизировать_каталог(путь.parent)
    except OSError as ошибка:
        raise ОшибкаОтчёта(f"не удалось атомарно записать {путь}: {ошибка}") from ошибка
    finally:
        if дескриптор is not None:
            os.close(дескриптор)
        try:
            временный.unlink()
        except FileNotFoundError:
            pass


def атомарно_записать_текст(путь: Path, текст: str) -> None:
    атомарно_записать_байты(путь, текст.encode("utf-8"))


def прочитать_машинную_запись(путь: Path) -> tuple[object, bytes]:
    проверить_обычный_путь(путь, "машинная запись")
    try:
        байты = путь.read_bytes()
        значение = json.loads(байты.decode("utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as ошибка:
        raise ОшибкаОтчёта(f"не удалось прочитать JSON {путь}: {ошибка}") from ошибка
    return значение, байты


def проверить_строку(
    значение: object,
    поле: str,
    *,
    разрешить_пустую: bool = False,
) -> str:
    if not isinstance(значение, str):
        raise ОшибкаОтчёта(f"поле {поле} должно быть строкой")
    if not разрешить_пустую and not значение:
        raise ОшибкаОтчёта(f"поле {поле} не должно быть пустым")
    if any(
        unicodedata.category(знак) in {"Cc", "Zl", "Zp"}
        for знак in значение
    ):
        raise ОшибкаОтчёта(
            f"поле {поле} содержит управляющий или строковый разделитель"
        )
    return значение


def проверить_идентификатор(значение: object) -> str:
    if not isinstance(значение, str) or КАНОНИЧЕСКИЙ_ИДЕНТИФИКАТОР.fullmatch(значение) is None:
        raise ОшибкаОтчёта("идентификатор запуска должен быть каноническим UUID")
    try:
        канонический = str(uuid.UUID(значение))
    except ValueError as ошибка:
        raise ОшибкаОтчёта("идентификатор запуска должен быть каноническим UUID") from ошибка
    if канонический != значение:
        raise ОшибкаОтчёта("идентификатор запуска должен быть lowercase UUID")
    return значение


def проверить_наблюдения(значение: object) -> list[dict[str, object]]:
    if not isinstance(значение, list):
        raise ОшибкаОтчёта("наблюдения должны быть списком")
    результат: list[dict[str, object]] = []
    ключи: set[str] = set()
    for номер, наблюдение in enumerate(значение, start=1):
        if not isinstance(наблюдение, dict) or set(наблюдение) != ПОЛЯ_НАБЛЮДЕНИЯ:
            raise ОшибкаОтчёта(
                f"неверный набор полей наблюдения smoke-check: {номер}"
            )
        ключ = проверить_аналитический_ключ(
            наблюдение["ключ_проверки"],
            f"ключ_проверки наблюдения {номер}",
        )
        приведённый = ключ.casefold()
        if приведённый in ключи:
            raise ОшибкаОтчёта(
                f"повторный ключ проверки в наблюдениях smoke-check: {ключ}"
            )
        ключи.add(приведённый)
        проверить_строку(
            наблюдение["название"],
            f"название наблюдения {номер}",
        )
        if наблюдение["статус"] not in СТАТУСЫ:
            raise ОшибкаОтчёта(
                f"неверный статус наблюдения smoke-check: {номер}"
            )
        длительность = наблюдение["длительность_наносекунды"]
        if (
            isinstance(длительность, bool)
            or not isinstance(длительность, int)
            or длительность < 0
        ):
            raise ОшибкаОтчёта(
                f"неверная длительность наблюдения smoke-check: {номер}"
            )
        результат.append(наблюдение)
    return результат


def проверить_аналитический_ключ(значение: object, поле: str) -> str:
    ключ = проверить_строку(значение, поле)
    путь = PurePosixPath(ключ)
    if (
        ключ != unicodedata.normalize("NFC", ключ)
        or "\\" in ключ
        or путь.is_absolute()
        or путь.as_posix() != ключ
        or any(часть in {"", ".", ".."} for часть in путь.parts)
    ):
        raise ОшибкаОтчёта(f"поле {поле} не является каноническим ключом")
    return ключ


def выполнить_чтение_репозитория(корень: Path, *аргументы: str) -> bytes:
    окружение = os.environ.copy()
    for имя in (
        "GIT_DIR",
        "GIT_WORK_TREE",
        "GIT_INDEX_FILE",
        "GIT_COMMON_DIR",
        "GIT_OBJECT_DIRECTORY",
        "GIT_ALTERNATE_OBJECT_DIRECTORIES",
        "GIT_REPLACE_REF_BASE",
    ):
        окружение.pop(имя, None)
    окружение.update(
        {
            "GIT_OPTIONAL_LOCKS": "0",
            "GIT_NO_REPLACE_OBJECTS": "1",
            "LC_ALL": "C",
        }
    )
    итог = subprocess.run(
        ["git", "-C", str(корень), *аргументы],
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=окружение,
    )
    if итог.returncode != 0:
        пояснение = итог.stderr.decode("utf-8", errors="replace").strip()
        raise ОшибкаОтчёта(
            "не удалось прочитать Git-снимок"
            + (f": {пояснение}" if пояснение else "")
        )
    return итог.stdout


def добавить_часть_отпечатка(
    хэш: "hashlib._Hash",
    метка: str,
    байты: bytes,
) -> None:
    метка_байты = метка.encode("utf-8")
    хэш.update(len(метка_байты).to_bytes(8, "big"))
    хэш.update(метка_байты)
    хэш.update(len(байты).to_bytes(8, "big"))
    хэш.update(байты)


def проверить_чистоту_подмодулей(корень: Path) -> None:
    состояние = выполнить_чтение_репозитория(
        корень,
        "status",
        "--porcelain=v2",
        "-z",
        "--untracked-files=all",
        "--ignore-submodules=none",
        "--",
        ".",
    )
    for строка in состояние.split(b"\0"):
        if not строка.startswith((b"1 ", b"2 ", b"u ")):
            continue
        части = строка.split(b" ", 8)
        if (
            len(части) > 2
            and len(части[2]) == 4
            and части[2].startswith(b"S")
            and части[2][2:] != b".."
        ):
            raise ОшибкаОтчёта(
                "Git-снимок содержит изменённый подмодуль"
            )


def вычислить_отпечаток_снимка(
    корень_репозитория: str | Path,
    сессия: str | Path,
) -> str:
    корень = Path(корень_репозитория).resolve()
    сессия_путь = PurePosixPath(Path(сессия).as_posix())
    if сессия_путь.is_absolute() or any(
        часть in {"", ".", ".."} for часть in сессия_путь.parts
    ):
        raise ОшибкаОтчёта("путь сессии для отпечатка неканоничен")
    исключённый_отчёт = (сессия_путь / ИМЯ_ОТЧЁТА).as_posix()
    исключённые_запуски = (
        сессия_путь / ОТНОСИТЕЛЬНЫЙ_КАТАЛОГ_ЗАПУСКОВ.as_posix()
    ).as_posix()
    пути_для_разницы = [
        ".",
        f":(exclude){исключённый_отчёт}",
        f":(exclude){исключённые_запуски}",
        f":(exclude){исключённые_запуски}/**",
    ]
    проверить_чистоту_подмодулей(корень)
    вершина = выполнить_чтение_репозитория(
        корень, "rev-parse", "--verify", "HEAD"
    ).strip()
    индекс = выполнить_чтение_репозитория(
        корень,
        "diff",
        "--binary",
        "--no-ext-diff",
        "--no-textconv",
        "--ignore-submodules=none",
        "--cached",
        "HEAD",
        "--",
        *пути_для_разницы,
    )
    рабочее_дерево = выполнить_чтение_репозитория(
        корень,
        "diff",
        "--binary",
        "--no-ext-diff",
        "--no-textconv",
        "--ignore-submodules=none",
        "--",
        *пути_для_разницы,
    )
    неотслеживаемые = выполнить_чтение_репозитория(
        корень, "ls-files", "--others", "--exclude-standard", "-z", "--", "."
    )
    хэш = hashlib.sha256()
    добавить_часть_отпечатка(хэш, "вершина", вершина)
    добавить_часть_отпечатка(хэш, "индекс", индекс)
    добавить_часть_отпечатка(хэш, "рабочее_дерево", рабочее_дерево)
    for исходное_имя in sorted(неотслеживаемые.split(b"\0")):
        if not исходное_имя:
            continue
        try:
            имя = исходное_имя.decode("utf-8")
        except UnicodeError as ошибка:
            raise ОшибкаОтчёта(
                "Git-снимок содержит не-UTF-8 путь"
            ) from ошибка
        if имя == исключённый_отчёт or (
            имя == исключённые_запуски
            or имя.startswith(f"{исключённые_запуски}/")
        ):
            continue
        каноническое_имя = проверить_аналитический_ключ(имя, "путь Git-снимка")
        путь = корень / Path(каноническое_имя)
        try:
            сведения = путь.lstat()
            if stat.S_ISREG(сведения.st_mode):
                тип = "файл"
                содержимое = путь.read_bytes()
            elif stat.S_ISLNK(сведения.st_mode):
                тип = "символическая_ссылка"
                содержимое = os.fsencode(os.readlink(путь))
            else:
                raise ОшибкаОтчёта(
                    f"неотслеживаемый путь имеет опасный тип: {имя}"
                )
        except OSError as ошибка:
            raise ОшибкаОтчёта(
                f"не удалось прочитать неотслеживаемый путь: {имя}"
            ) from ошибка
        добавить_часть_отпечатка(
            хэш,
            f"неотслеживаемый:{каноническое_имя}:{тип}:{stat.S_IMODE(сведения.st_mode):o}",
            содержимое,
        )
    return f"sha256:{хэш.hexdigest()}"


def проверить_полные_наборы(значение: object) -> list[str]:
    if not isinstance(значение, list):
        raise ОшибкаОтчёта("полные_наборы должны быть списком")
    результат: list[str] = []
    приведённые: set[str] = set()
    for номер, значение_ключа in enumerate(значение, start=1):
        ключ = проверить_аналитический_ключ(
            значение_ключа, f"полный набор { номер}"
        )
        приведённый = ключ.casefold()
        if приведённый in приведённые:
            raise ОшибкаОтчёта(f"повторный полный набор: {ключ}")
        приведённые.add(приведённый)
        результат.append(ключ)
    return результат


def проверить_профиль_проверки(
    значение: object,
    план: Sequence[dict[str, str]] | None,
    наблюдения: Sequence[dict[str, object]],
    состояние: str,
) -> dict[str, object]:
    if not isinstance(значение, dict) or set(значение) != ПОЛЯ_ПРОФИЛЯ_ПРОВЕРКИ:
        raise ОшибкаОтчёта("неверный набор полей профиля проверки")
    класс = значение["класс"]
    if not isinstance(класс, str) or класс not in КЛАССЫ_ПРОВЕРОК:
        raise ОшибкаОтчёта("неверный класс проверки")
    отпечаток = значение["отпечаток_снимка"]
    if not isinstance(отпечаток, str) or re.fullmatch(
        r"sha256:[0-9a-f]{64}", отпечаток
    ) is None:
        raise ОшибкаОтчёта("неверный отпечаток Git-снимка")
    полные_наборы = проверить_полные_наборы(
        значение["полные_наборы"]
    )
    основание = значение["основание"]
    идентификатор_отказа = значение["идентификатор_отказа"]
    свидетельство = значение["ожидаемое_свидетельство"]
    if основание is not None and not isinstance(основание, str):
        raise ОшибкаОтчёта("основание профиля должно быть строкой или null")
    if идентификатор_отказа is not None:
        проверить_идентификатор(идентификатор_отказа)
    if свидетельство is not None:
        проверить_строку(свидетельство, "ожидаемое_свидетельство")
    if класс == "адресная":
        if полные_наборы or any(
            значение[поле] is not None
            for поле in (
                "основание",
                "идентификатор_отказа",
                "ожидаемое_свидетельство",
            )
        ):
            raise ОшибкаОтчёта("адресная проверка не объявляет полные наборы или диагностику")
    elif класс == "диагностическая":
        if not полные_наборы or основание not in ОСНОВАНИЯ_ДИАГНОСТИКИ or not свидетельство:
            raise ОшибкаОтчёта("диагностическая проверка требует наборы, основание и ожидаемое свидетельство")
        if (
            основание == "локализация_наблюдаемого_отказа"
        ) != (идентификатор_отказа is not None):
            raise ОшибкаОтчёта("локализация требует точный UUID предшествующего неуспешного запуска")
    else:
        if any(
            значение[поле] is not None
            for поле in (
                "основание",
                "идентификатор_отказа",
                "ожидаемое_свидетельство",
            )
        ):
            raise ОшибкаОтчёта("полная проверка не объявляет диагностику")
        ожидаемые_ключи = (
            [элемент["ключ_проверки"] for элемент in план]
            if план is not None
            else []
        )
        if полные_наборы != ожидаемые_ключи:
            raise ОшибкаОтчёта("наборы полной проверки не выведены из фактического плана")
    if класс != "полная" and (план is not None or наблюдения):
        raise ОшибкаОтчёта("план и наблюдения допустимы только для полной проверки")
    if состояние == "выполняется" and (план is not None or наблюдения):
        raise ОшибкаОтчёта("активная профилированная запись содержит наблюдения")
    return значение


def проверить_план_наблюдений(
    значение: object,
) -> list[dict[str, str]] | None:
    if значение is None:
        return None
    if not isinstance(значение, list):
        raise ОшибкаОтчёта(
            "план наблюдений smoke-check должен быть списком или null"
        )
    результат: list[dict[str, str]] = []
    приведённые_ключи: set[str] = set()
    for номер, элемент in enumerate(значение, start=1):
        if not isinstance(элемент, dict) or set(элемент) != ПОЛЯ_ЭЛЕМЕНТА_ПЛАНА:
            raise ОшибкаОтчёта(
                f"неверный набор полей плана наблюдений smoke-check: {номер}"
            )
        ключ = проверить_аналитический_ключ(
            элемент["ключ_проверки"],
            f"ключ_проверки плана {номер}",
        )
        название = проверить_строку(
            элемент["название"],
            f"название плана {номер}",
        )
        приведённый = ключ.casefold()
        if приведённый in приведённые_ключи:
            raise ОшибкаОтчёта(
                f"регистронезависимая коллизия ключа в плане smoke-check: {ключ}"
            )
        приведённые_ключи.add(приведённый)
        результат.append({"ключ_проверки": ключ, "название": название})
    return результат


def проверить_префикс_наблюдений(
    план: Sequence[dict[str, str]] | None,
    наблюдения: Sequence[dict[str, object]],
) -> None:
    if план is None:
        if наблюдения:
            raise ОшибкаОтчёта(
                "наблюдения smoke-check записаны до формирования плана"
            )
        return
    if len(наблюдения) > len(план):
        raise ОшибкаОтчёта("наблюдения smoke-check длиннее плана")
    for номер, наблюдение in enumerate(наблюдения):
        if any(
            наблюдение[поле] != план[номер][поле]
            for поле in ("ключ_проверки", "название")
        ):
            raise ОшибкаОтчёта(
                "наблюдения smoke-check не образуют точный префикс плана"
            )


def проверить_текущую_проверку(
    значение: object,
    план: Sequence[dict[str, str]] | None,
    наблюдения: Sequence[dict[str, object]],
) -> dict[str, object] | None:
    if значение is None:
        return None
    if (
        not isinstance(значение, dict)
        or set(значение) != ПОЛЯ_ТЕКУЩЕЙ_ПРОВЕРКИ
        or план is None
        or len(наблюдения) >= len(план)
    ):
        raise ОшибкаОтчёта("неверная текущая проверка smoke-check")
    for поле in ("ключ_проверки", "название"):
        проверить_строку(значение[поле], f"{поле} текущей проверки")
        if значение[поле] != план[len(наблюдения)][поле]:
            raise ОшибкаОтчёта(
                "текущая проверка smoke-check не совпадает со следующим шагом плана"
            )
    начало = значение["начало_монотонные_наносекунды"]
    if isinstance(начало, bool) or not isinstance(начало, int) or начало < 0:
        raise ОшибкаОтчёта(
            "неверное монотонное начало текущей проверки smoke-check"
        )
    if any(наблюдение["статус"] != "успешно" for наблюдение in наблюдения):
        raise ОшибкаОтчёта(
            "текущая проверка smoke-check следует после fail-fast исхода"
        )
    return значение


def является_запуском_полной_проверки(
    корень: Path,
    команда: Sequence[str],
) -> bool:
    if "--list" in команда:
        return False
    канонический = (корень / ПУТЬ_ПОЛНОЙ_ПРОВЕРКИ).resolve()
    if not команда:
        return False

    def совпадает(аргумент: str) -> bool:
        путь = Path(аргумент)
        if not путь.is_absolute():
            путь = корень / путь
        try:
            return путь.resolve() == канонический
        except OSError:
            return False

    if совпадает(команда[0]):
        return True
    имя_исполнителя = Path(команда[0]).name.lower()
    if re.fullmatch(r"python(?:[0-9]+(?:\.[0-9]+)*)?", имя_исполнителя) is None:
        return False
    индекс = 1
    while индекс < len(команда) and команда[индекс] in {
        "-B", "-E", "-I", "-O", "-OO", "-P", "-s", "-S", "-u"
    }:
        индекс += 1
    return индекс < len(команда) and совпадает(команда[индекс])


def прочитать_конверт_наблюдений(
    путь: Path,
    идентификатор: str,
) -> tuple[
    list[dict[str, str]] | None,
    list[dict[str, object]],
    dict[str, object] | None,
]:
    if not путь.exists():
        raise ОшибкаОтчёта("обязательный конверт наблюдений smoke-check отсутствует")
    try:
        значение, байты = прочитать_машинную_запись(путь)
    except ОшибкаОтчёта as ошибка:
        raise ОшибкаОтчёта(
            "не удалось прочитать обязательный конверт наблюдений smoke-check"
        ) from ошибка
    if байты != канонические_машинные_байты(значение):
        raise ОшибкаОтчёта("конверт наблюдений smoke-check неканоничен")
    if not isinstance(значение, dict) or set(значение) != ПОЛЯ_КОНВЕРТА_НАБЛЮДЕНИЙ:
        raise ОшибкаОтчёта("неверный набор полей конверта наблюдений smoke-check")
    if значение["схема"] != СХЕМА_НАБЛЮДЕНИЙ_ПОЛНОЙ_ПРОВЕРКИ:
        raise ОшибкаОтчёта("неверная схема конверта наблюдений smoke-check")
    if значение["идентификатор_запуска"] != идентификатор:
        raise ОшибкаОтчёта(
            "конверт наблюдений smoke-check принадлежит другому запуску"
        )
    план = проверить_план_наблюдений(значение["план"])
    наблюдения = проверить_наблюдения(значение["наблюдения"])
    проверить_префикс_наблюдений(план, наблюдения)
    текущая_проверка = проверить_текущую_проверку(
        значение["текущая_проверка"],
        план,
        наблюдения,
    )
    return план, наблюдения, текущая_проверка


def начальный_конверт_наблюдений(
    идентификатор: str,
) -> dict[str, object]:
    return {
        "схема": СХЕМА_НАБЛЮДЕНИЙ_ПОЛНОЙ_ПРОВЕРКИ,
        "идентификатор_запуска": идентификатор,
        "план": None,
        "наблюдения": [],
        "текущая_проверка": None,
    }


def проверить_согласованность_наблюдений(
    план: Sequence[dict[str, str]] | None,
    наблюдения: Sequence[dict[str, object]],
    статус: str,
    длительность_наносекунды: int,
) -> None:
    проверить_префикс_наблюдений(план, наблюдения)
    неуспешные = [
        номер
        for номер, наблюдение in enumerate(наблюдения)
        if наблюдение["статус"] != "успешно"
    ]
    if len(неуспешные) > 1 or (
        неуспешные and неуспешные[0] != len(наблюдения) - 1
    ):
        raise ОшибкаОтчёта(
            "наблюдения smoke-check нарушают последовательный fail-fast"
        )
    if статус == "успешно" and (
        план is None
        or len(наблюдения) != len(план)
        or неуспешные
    ):
        raise ОшибкаОтчёта(
            "успешный smoke-check не подтвердил полный успешный тестовый план"
        )
    сумма = sum(
        int(наблюдение["длительность_наносекунды"])
        for наблюдение in наблюдения
    )
    if сумма > длительность_наносекунды:
        raise ОшибкаОтчёта(
            "сумма длительностей тестов превышает длительность smoke-check"
        )


def проверить_запись(
    значение: object,
    имя_файла: str,
    сессия: str,
) -> dict[str, object]:
    if not isinstance(значение, dict):
        raise ОшибкаОтчёта(f"неверный набор полей записи: {имя_файла}")
    схема = значение.get("схема")
    if схема == СХЕМА_ЗАПУСКА:
        ожидаемые_поля = ПОЛЯ_ЗАПИСИ
    elif схема == СХЕМА_ЗАПУСКА_С_НАБЛЮДЕНИЯМИ:
        ожидаемые_поля = ПОЛЯ_ЗАПИСИ_С_НАБЛЮДЕНИЯМИ
    elif схема == СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА:
        ожидаемые_поля = ПОЛЯ_ПРОФИЛИРОВАННОЙ_ЗАПИСИ
    else:
        raise ОшибкаОтчёта(f"неверная схема записи: {имя_файла}")
    if set(значение) != ожидаемые_поля:
        raise ОшибкаОтчёта(f"неверный набор полей записи: {имя_файла}")
    совпадение = ИМЯ_ФАЙЛА_ЗАПУСКА.fullmatch(имя_файла)
    if совпадение is None:
        raise ОшибкаОтчёта(f"неверное имя файла запуска: {имя_файла}")
    идентификатор = проверить_идентификатор(значение["идентификатор"])
    if идентификатор != совпадение.group("идентификатор"):
        raise ОшибкаОтчёта(f"UUID записи не совпадает с именем: {имя_файла}")
    if значение["сессия"] != сессия:
        raise ОшибкаОтчёта(f"запись принадлежит другой сессии: {имя_файла}")
    порядок = значение["порядок"]
    if isinstance(порядок, bool) or not isinstance(порядок, int) or порядок <= 0:
        raise ОшибкаОтчёта(f"неверный порядок записи: {имя_файла}")
    if порядок != int(совпадение.group("порядок")):
        raise ОшибкаОтчёта(f"порядок записи не совпадает с именем: {имя_файла}")
    проверить_строку(значение["исполнитель"], "исполнитель")
    проверить_строку(значение["вызов"], "вызов")
    состояние = значение["состояние"]
    if состояние not in СОСТОЯНИЯ:
        raise ОшибкаОтчёта(f"неверное состояние записи: {имя_файла}")
    if схема in {
        СХЕМА_ЗАПУСКА_С_НАБЛЮДЕНИЯМИ,
        СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА,
    }:
        план = проверить_план_наблюдений(значение["план"])
        наблюдения = проверить_наблюдения(значение["наблюдения"])
        проверить_префикс_наблюдений(план, наблюдения)
        if состояние == "выполняется" and (
            план is not None or наблюдения
        ):
            raise ОшибкаОтчёта(
                f"активная запись содержит план или наблюдения: {имя_файла}"
            )
        if схема == СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА:
            проверить_профиль_проверки(
                значение["профиль_проверки"],
                план,
                наблюдения,
                состояние,
            )

    терминальные_поля = (
        значение["длительность_наносекунды"],
        значение["статус"],
        значение["код_завершения"],
        значение["пояснение"],
    )
    if состояние == "выполняется":
        if any(поле is not None for поле in терминальные_поля):
            raise ОшибкаОтчёта(
                f"активная запись содержит терминальные поля: {имя_файла}"
            )
        return значение

    длительность = значение["длительность_наносекунды"]
    if (
        isinstance(длительность, bool)
        or not isinstance(длительность, int)
        or длительность < 0
    ):
        raise ОшибкаОтчёта(f"неверная длительность записи: {имя_файла}")
    статус = значение["статус"]
    if статус not in СТАТУСЫ:
        raise ОшибкаОтчёта(f"неверный статус записи: {имя_файла}")
    код = значение["код_завершения"]
    if код is not None and (isinstance(код, bool) or not isinstance(код, int)):
        raise ОшибкаОтчёта(f"неверный код завершения: {имя_файла}")
    if (
        (статус == "успешно" and код != 0)
        or (статус == "неуспешно" and (код is None or код <= 0))
        or (статус == "прервано" and (код is None or код >= 0))
        or (статус == "не завершено" and (код is None or код <= 0))
    ):
        raise ОшибкаОтчёта(
            f"статус записи противоречит коду завершения: {имя_файла}"
        )
    пояснение = значение["пояснение"]
    if пояснение is not None:
        проверить_строку(
            пояснение,
            "пояснение",
            разрешить_пустую=True,
        )
    if схема == СХЕМА_ЗАПУСКА_С_НАБЛЮДЕНИЯМИ or (
        схема == СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА
        and значение["профиль_проверки"]["класс"] == "полная"
    ):
        проверить_согласованность_наблюдений(
            план,
            наблюдения,
            статус,
            длительность,
        )
    return значение


def прочитать_записи(
    каталог: Path,
    сессия: str,
) -> list[tuple[Path, dict[str, object], bytes]]:
    if not каталог.exists():
        raise ОшибкаОтчёта(f"каталог запусков отсутствует: {каталог}")
    if каталог.is_symlink() or not каталог.is_dir():
        raise ОшибкаОтчёта(f"каталог запусков должен быть обычным каталогом: {каталог}")
    записи: list[tuple[Path, dict[str, object], bytes]] = []
    for путь in sorted(каталог.iterdir(), key=lambda элемент: элемент.name):
        if путь.name in {ИМЯ_СНИМКА, ИМЯ_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ}:
            if путь.is_symlink() or not путь.is_file():
                raise ОшибкаОтчёта(
                    f"служебный файл должен быть обычным файлом: {путь.name}"
                )
            continue
        if ИМЯ_ФАЙЛА_ЗАПУСКА.fullmatch(путь.name) is None:
            raise ОшибкаОтчёта(f"неизвестный файл в каталоге запусков: {путь.name}")
        значение, байты = прочитать_машинную_запись(путь)
        запись = проверить_запись(значение, путь.name, сессия)
        записи.append((путь, запись, байты))
    if not записи:
        raise ОшибкаОтчёта("машинный журнал не содержит ни одного запуска")
    порядки = [int(запись["порядок"]) for _, запись, _ in записи]
    идентификаторы = [str(запись["идентификатор"]) for _, запись, _ in записи]
    if len(set(порядки)) != len(порядки):
        raise ОшибкаОтчёта("машинный журнал содержит повтор порядка")
    if len(set(идентификаторы)) != len(идентификаторы):
        raise ОшибкаОтчёта("машинный журнал содержит повтор UUID")
    return sorted(
        записи,
        key=lambda элемент: (
            int(элемент[1]["порядок"]),
            str(элемент[1]["идентификатор"]),
        ),
    )


def журнал_возобновления_существует(каталог: Path) -> bool:
    путь = каталог / ИМЯ_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ
    return путь.exists() or путь.is_symlink()


def запретить_действие_при_возобновлении(
    каталог: Path,
    действие: str,
) -> None:
    if журнал_возобновления_существует(каталог):
        raise ОшибкаОтчёта(
            f"{действие} запрещено до завершения журнала возобновления"
        )


def экранировать_табличный_текст(значение: str) -> str:
    return значение.replace("\\", "\\\\").replace("|", "\\|")


def округлить_до_миллисекунд(наносекунды: int) -> int:
    return (наносекунды + 500_000) // 1_000_000


def отформатировать_секунды(миллисекунды: int, *, активный: bool = False) -> str:
    if активный:
        return "0,000"
    целые, дробные = divmod(миллисекунды, 1000)
    if дробные == 0:
        return str(целые)
    return f"{целые},{дробные:03d}".rstrip("0")


def табличная_строка(ячейки: Sequence[str], ширины: Sequence[int]) -> str:
    return "| " + " | ".join(
        ячейка.ljust(ширины[номер])
        for номер, ячейка in enumerate(ячейки)
    ) + " |"


НОРМАТИВНЫЙ_КОНТУР_УСПЕШНОЙ_СЕССИИ = (
    "адресные_красные_и_зелёные_проверки",
    "изменённые_плановые_контракты",
    "свежесть",
    "связность_сессии",
    "финальная_комплексная_проверка",
    "закрытие_отчёта",
    "локальный_коммит_на_master_без_продолжения",
)


def профиль_записи(запись: dict[str, object]) -> dict[str, object] | None:
    if запись.get("схема") != СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА:
        return None
    профиль = запись.get("профиль_проверки")
    return профиль if isinstance(профиль, dict) else None


def история_схем_несовместима(записи: Sequence[dict[str, object]]) -> bool:
    первый_профилированный_порядок = min(
        (
            int(запись["порядок"])
            for запись in записи
            if запись.get("схема") == СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА
        ),
        default=None,
    )
    return bool(
        первый_профилированный_порядок is not None
        and (
            any(
                запись.get("схема") == СХЕМА_ЗАПУСКА_С_НАБЛЮДЕНИЯМИ
                for запись in записи
            )
            or any(
                int(запись["порядок"])
                > первый_профилированный_порядок
                and запись.get("схема") != СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА
                for запись in записи
            )
        )
    )


def построить_план_успешной_сессии(
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
    текущий_отпечаток: str | None = None,
) -> dict[str, object]:
    все_записи = sorted(
        (запись for _, запись, _ in записи),
        key=lambda запись: int(запись["порядок"]),
    )
    профилированные = sorted(
        (
            запись
            for _, запись, _ in записи
            if профиль_записи(запись) is not None
        ),
        key=lambda запись: int(запись["порядок"]),
    )
    все_полные = [
        запись
        for запись in профилированные
        if профиль_записи(запись).get("класс") == "полная"
    ]
    завершённые_полные = [
        запись
        for запись in все_полные
        if запись.get("состояние") == "завершён"
    ]
    успешные_полные = [
        запись
        for запись in завершённые_полные
        if запись.get("статус") == "успешно"
    ]
    дублирования: list[dict[str, object]] = []
    отдельные_диагностики: list[dict[str, object]] = []
    недействительные_локализации: list[str] = []
    допустимые_локализации: set[str] = set()
    по_идентификатору = {
        str(запись.get("идентификатор")): запись
        for запись in профилированные
    }
    for запись in профилированные:
        профиль = профиль_записи(запись)
        if (
            запись.get("состояние") != "завершён"
            or профиль.get("класс") != "диагностическая"
            or профиль.get("основание")
            != "локализация_наблюдаемого_отказа"
        ):
            continue
        идентификатор = str(запись.get("идентификатор"))
        отказ = по_идентификатору.get(
            str(профиль.get("идентификатор_отказа"))
        )
        профиль_отказа = профиль_записи(отказ) if отказ is not None else None
        связь_действительна = bool(
            отказ is not None
            and int(отказ.get("порядок", 0)) < int(запись.get("порядок", 0))
            and отказ.get("статус") == "неуспешно"
            and профиль_отказа is not None
            and профиль_отказа.get("отпечаток_снимка")
            == профиль.get("отпечаток_снимка")
        )
        if связь_действительна:
            допустимые_локализации.add(идентификатор)
        else:
            недействительные_локализации.append(идентификатор)
    финальная = все_полные[-1] if все_полные else None
    финальный_профиль = (
        профиль_записи(финальная) if финальная is not None else None
    )
    if финальная is not None:
        финальные_наборы = {
            str(ключ).casefold(): str(ключ)
            for ключ in финальный_профиль.get("полные_наборы", [])
        }
        for запись in профилированные:
            профиль = профиль_записи(запись)
            if запись.get("состояние") != "завершён" or профиль.get(
                "класс"
            ) not in {"диагностическая", "полная"}:
                continue
            пересечение = sorted({
                финальные_наборы[ключ.casefold()]
                for ключ in профиль.get("полные_наборы", [])
                if (
                    профиль.get("отпечаток_снимка")
                    == финальный_профиль.get("отпечаток_снимка")
                    and ключ.casefold() in финальные_наборы
                )
            })
            объявленные_наборы = {
                str(ключ).casefold(): str(ключ)
                for ключ in профиль.get("полные_наборы", [])
            }
            непокрытые = sorted(
                исходный
                for ключ, исходный in объявленные_наборы.items()
                if ключ not in финальные_наборы
            )
            тот_же_снимок = bool(
                профиль.get("отпечаток_снимка")
                == финальный_профиль.get("отпечаток_снимка")
            )
            if профиль.get("класс") == "диагностическая" and непокрытые:
                отдельные_диагностики.append(
                    {
                        "идентификатор": запись.get("идентификатор"),
                        "наборы": непокрытые,
                        "длительность_наносекунды": запись.get(
                            "длительность_наносекунды"
                        ),
                        "статус": запись.get("статус"),
                        "основание": профиль.get("основание"),
                        "ожидаемое_свидетельство": профиль.get(
                            "ожидаемое_свидетельство"
                        ),
                        "тот_же_снимок": тот_же_снимок,
                    }
                )
            if not пересечение:
                continue
            if int(запись.get("порядок", 0)) >= int(
                финальная.get("порядок", 0)
            ):
                continue
            разрешено = False
            if профиль.get("класс") == "диагностическая" and профиль.get(
                "основание"
            ) == "локализация_наблюдаемого_отказа":
                разрешено = str(
                    запись.get("идентификатор")
                ) in допустимые_локализации
            дублирования.append(
                {
                    "идентификатор": запись.get("идентификатор"),
                    "класс": профиль.get("класс"),
                    "наборы": пересечение,
                    "длительность_наносекунды": запись.get("длительность_наносекунды"),
                    "статус": запись.get("статус"),
                    "основание": профиль.get("основание"),
                    "ожидаемое_свидетельство": профиль.get("ожидаемое_свидетельство"),
                    "разрешено": разрешено,
                }
            )
    неразрешённые = [дубль for дубль in дублирования if not дубль["разрешено"]]
    неуспешные_актуальные_диагностики = [
        диагностика
        for диагностика in отдельные_диагностики
        if диагностика["тот_же_снимок"]
        and диагностика["статус"] != "успешно"
    ]
    счётчик_полных_снимков: dict[str, int] = {}
    for запись in завершённые_полные:
        отпечаток = str(профиль_записи(запись).get("отпечаток_снимка"))
        счётчик_полных_снимков[отпечаток] = (
            счётчик_полных_снимков.get(отпечаток, 0) + 1
        )
    повторные_полные_снимки = sorted(
        отпечаток
        for отпечаток, число in счётчик_полных_снимков.items()
        if число > 1
    )
    есть_выполняющиеся = any(
        запись.get("состояние") == "выполняется" for запись in все_записи
    )
    максимальный_порядок = max(
        (int(запись["порядок"]) for запись in все_записи),
        default=0,
    )
    финальный_полный_последний = bool(
        финальная is not None
        and int(финальная["порядок"]) == максимальный_порядок
    )
    финал_успешен = bool(
        финальная is not None
        and финальная.get("состояние") == "завершён"
        and финальная.get("статус") == "успешно"
    )
    несовместимая_история = история_схем_несовместима(все_записи)
    снимок_совпадает = bool(
        текущий_отпечаток is not None
        and финальный_профиль is not None
        and финальный_профиль.get("отпечаток_снимка")
        == текущий_отпечаток
    )
    доказанные_условия = {
        "нет_активных": not есть_выполняющиеся,
        "финальная_полная_последняя": финальный_полный_последний,
        "финальная_полная_успешна": финал_успешен,
        "ровно_один_успешный_полный_прогон": len(успешные_полные) == 1,
        "нет_запрещённых_перекрытий": not неразрешённые
        and not повторные_полные_снимки,
        "локализации_связаны_с_предшествующим_отказом": not недействительные_локализации,
        "непокрытые_диагностики_успешны": not неуспешные_актуальные_диагностики,
        "совместимая_история": not несовместимая_история,
        "снимок_совпадает": снимок_совпадает,
    }
    готов = all(доказанные_условия.values())
    return {
        "состояние": "готов" if готов else "не готов",
        "нормативный_контур": list(
            НОРМАТИВНЫЙ_КОНТУР_УСПЕШНОЙ_СЕССИИ
        ),
        "доказанные_условия": доказанные_условия,
        "полные_попытки": len(завершённые_полные),
        "полные_прогоны": len(успешные_полные),
        "последний_полный_статус": финальная.get("статус") if финальная is not None else None,
        "отпечаток_финального_снимка": финальный_профиль.get("отпечаток_снимка") if финальный_профиль is not None else None,
        "финальный_полный_последний": финальный_полный_последний,
        "есть_выполняющиеся": есть_выполняющиеся,
        "несовместимая_история": несовместимая_история,
        "дублирования": дублирования,
        "отдельные_диагностики": отдельные_диагностики,
        "повторные_полные_снимки": повторные_полные_снимки,
        "недействительные_локализации": недействительные_локализации,
    }


def проверить_порядок_проверок(
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
    текущий_отпечаток: str | None = None,
) -> dict[str, object]:
    план = построить_план_успешной_сессии(записи, текущий_отпечаток)
    if план["есть_выполняющиеся"]:
        raise ОшибкаОтчёта("экономный план содержит выполняющуюся запись")
    if план["несовместимая_история"]:
        raise ОшибкаОтчёта("v1/v2 нельзя добавлять после v3 или смешивать v2 с v3")
    if план["недействительные_локализации"]:
        raise ОшибкаОтчёта("диагностика требует точный UUID предшествующего неуспешного запуска")
    if план["повторные_полные_снимки"]:
        raise ОшибкаОтчёта("полная проверка повторена на неизменённом снимке")
    if any(not дубль["разрешено"] for дубль in план["дублирования"]):
        raise ОшибкаОтчёта("обнаружено неразрешённое дублирование полной проверки")
    if any(
        диагностика["тот_же_снимок"]
        and диагностика["статус"] != "успешно"
        for диагностика in план["отдельные_диагностики"]
    ):
        raise ОшибкаОтчёта("непокрытая диагностика не была успешной")
    if план["полные_прогоны"] != 1:
        raise ОшибкаОтчёта("успешный план требует ровно один полный прогон")
    if план["последний_полный_статус"] != "успешно":
        raise ОшибкаОтчёта("последняя полная проверка не была успешной")
    if not план["финальный_полный_последний"]:
        raise ОшибкаОтчёта("финальная полная проверка должна быть последней записью")
    if текущий_отпечаток is None:
        raise ОшибкаОтчёта("текущий отпечаток снимка не передан")
    if план[
        "отпечаток_финального_снимка"
    ] != текущий_отпечаток:
        raise ОшибкаОтчёта("снимок изменился после финальной полной проверки")
    return план


def сформировать_строки_плана(
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
    текущий_отпечаток: str | None = None,
) -> list[str]:
    if not any(профиль_записи(запись) is not None for _, запись, _ in записи):
        return []
    план = построить_план_успешной_сессии(записи, текущий_отпечаток)
    строки = [f"Экономный порядок проверок: {план['состояние']}." ]
    for дубль in план["дублирования"]:
        секунды = отформатировать_секунды(
            округлить_до_миллисекунд(int(дубль["длительность_наносекунды"]))
        )
        статус = "разрешено" if дубль["разрешено"] else "не разрешено"
        строки.append(
            "Дублирование полного набора: "
            f"{статус}; {секунды} с; "
            f"результат: {дубль['статус']}; "
            f"наборы: {', '.join(дубль['наборы'])}; "
            f"основание: {дубль['основание'] or 'нет'}."
        )
    for диагностика in план["отдельные_диагностики"]:
        секунды = отформатировать_секунды(
            округлить_до_миллисекунд(
                int(диагностика["длительность_наносекунды"])
            )
        )
        строки.append(
            "Отдельная диагностическая проверка: "
            f"{секунды} с; "
            f"результат: {диагностика['статус']}; "
            f"наборы: {', '.join(диагностика['наборы'])}; "
            f"основание: {диагностика['основание']}."
        )
    return строки


def сформировать_блок(
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
    начальный_маркер: str,
    текущий_отпечаток: str | None = None,
) -> str:
    строки: list[tuple[str, str, str]] = []
    сумма_миллисекунд = 0
    for _, запись, _ in записи:
        вызов = экранировать_табличный_текст(
            f"[{запись['исполнитель']}] {запись['вызов']}"
        )
        if запись["состояние"] == "выполняется":
            длительность = "0,000 с"
            результат = "не завершено — нет итоговой записи"
        else:
            наносекунды = int(запись["длительность_наносекунды"])
            миллисекунды = округлить_до_миллисекунд(наносекунды)
            сумма_миллисекунд += миллисекунды
            длительность = f"{отформатировать_секунды(миллисекунды)} с"
            результат = str(запись["статус"])
            пояснение = запись["пояснение"]
            if пояснение:
                результат = f"{результат} — {пояснение}"
            результат = экранировать_табличный_текст(результат)
        строки.append((вызов, длительность, результат))

    заголовки = ("Вызов", "Длительность", "Результат")
    ширины = [
        max(len(заголовки[номер]), *(len(строка[номер]) for строка in строки))
        for номер in range(len(заголовки))
    ]
    таблица = [
        табличная_строка(заголовки, ширины),
        табличная_строка(tuple("-" * ширина for ширина in ширины), ширины),
        *(табличная_строка(строка, ширины) for строка in строки),
    ]
    итог = отформатировать_секунды(сумма_миллисекунд)
    строки_плана = сформировать_строки_плана(записи, текущий_отпечаток)
    дополнение_плана = ["", *строки_плана] if строки_плана else []
    return "\n".join(
        (
            начальный_маркер,
            "",
            *таблица,
            "",
            f"Общее время прямых запусков проверок: {итог} с.",
            *дополнение_плана,
            "",
            КОНЕЧНЫЙ_МАРКЕР,
        )
    )


def границы_управляемого_блока(текст: str) -> tuple[int, int, str]:
    начала = list(ЛЮБОЙ_НАЧАЛЬНЫЙ_МАРКЕР.finditer(текст))
    концы = list(КОНЕЧНЫЙ_МАРКЕР_СТРОКА.finditer(текст))
    if len(начала) != 1 or len(концы) != 1:
        raise ОшибкаОтчёта(
            "отчёт должен содержать ровно одну пару FUM-CHECK-RUNS marker"
        )
    начало = начала[0]
    конец = концы[0]
    if начало.end() >= конец.start():
        raise ОшибкаОтчёта("marker-пара отчёта переставлена или вложена")
    маркер = начало.group(0)
    if маркер != ОТКРЫТЫЙ_МАРКЕР and ЗАКРЫТЫЙ_МАРКЕР.fullmatch(маркер) is None:
        raise ОшибкаОтчёта("начальный marker отчёта имеет неизвестный формат")
    return начало.start(), конец.end(), маркер


def заменить_управляемый_блок_в_байтах(
    исходные_байты: bytes,
    новый_блок: str,
) -> bytes:
    try:
        текст = исходные_байты.decode("utf-8")
    except UnicodeError as ошибка:
        raise ОшибкаОтчёта(f"не удалось декодировать отчёт: {ошибка}") from ошибка
    начало, конец, _ = границы_управляемого_блока(текст)
    новый_текст = текст[:начало] + новый_блок + текст[конец:]
    return новый_текст.encode("utf-8")


def заменить_управляемый_блок(путь_отчёта: Path, новый_блок: str) -> None:
    try:
        исходные_байты = путь_отчёта.read_bytes()
    except OSError as ошибка:
        raise ОшибкаОтчёта(f"не удалось прочитать отчёт: {ошибка}") from ошибка
    новые_байты = заменить_управляемый_блок_в_байтах(
        исходные_байты,
        новый_блок,
    )
    if новые_байты != исходные_байты:
        атомарно_записать_байты(путь_отчёта, новые_байты)


def ожидаемый_снимок(
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
    сессия: str,
    отпечаток_закрытия: str | None = None,
) -> dict[str, object]:
    есть_профилированные = any(
        запись.get("схема") == СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА
        for _, запись, _ in записи
    )
    if есть_профилированные and (
        not isinstance(отпечаток_закрытия, str)
        or re.fullmatch(r"sha256:[0-9a-f]{64}", отпечаток_закрытия) is None
    ):
        raise ОшибкаОтчёта("v3-снимок требует отпечаток закрытия")
    if not есть_профилированные and отпечаток_закрытия is not None:
        raise ОшибкаОтчёта("исторический снимок не содержит отпечаток закрытия")
    снимок: dict[str, object] = {
        "схема": (
            СХЕМА_СНИМКА_С_ВЕРДИКТОМ
            if есть_профилированные
            else СХЕМА_СНИМКА
        ),
        "сессия": сессия,
        "файлы": [
            {"имя": путь.name, "sha256": хэш_содержимого(байты)}
            for путь, _, байты in записи
        ],
    }
    if есть_профилированные:
        снимок["отпечаток_закрытия"] = отпечаток_закрытия
    return снимок


def проверить_снимок(
    путь_снимка: Path,
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
    сессия: str,
) -> tuple[bytes, str | None]:
    значение, байты = прочитать_машинную_запись(путь_снимка)
    if not isinstance(значение, dict):
        raise ОшибкаОтчёта("снимок содержит неверный набор полей")
    схема = значение.get("схема")
    if схема == СХЕМА_СНИМКА:
        ожидаемые_поля = ПОЛЯ_СНИМКА
        отпечаток_закрытия = None
    elif схема == СХЕМА_СНИМКА_С_ВЕРДИКТОМ:
        ожидаемые_поля = ПОЛЯ_СНИМКА_С_ВЕРДИКТОМ
        отпечаток_закрытия = значение.get("отпечаток_закрытия")
        if not isinstance(отпечаток_закрытия, str) or re.fullmatch(
            r"sha256:[0-9a-f]{64}", отпечаток_закрытия
        ) is None:
            raise ОшибкаОтчёта("снимок содержит неверный отпечаток закрытия")
    else:
        raise ОшибкаОтчёта("снимок имеет неверную схему или сессию")
    if set(значение) != ожидаемые_поля:
        raise ОшибкаОтчёта("снимок содержит неверный набор полей")
    if значение["сессия"] != сессия:
        raise ОшибкаОтчёта("снимок имеет неверную схему или сессию")
    файлы = значение["файлы"]
    if not isinstance(файлы, list) or any(
        not isinstance(описание, dict)
        or set(описание) != ПОЛЯ_ФАЙЛА_СНИМКА
        or not isinstance(описание["имя"], str)
        or not isinstance(описание["sha256"], str)
        or re.fullmatch(r"[0-9a-f]{64}", описание["sha256"]) is None
        for описание in файлы
    ):
        raise ОшибкаОтчёта("снимок содержит неверный список файлов")
    if значение != ожидаемый_снимок(
        записи,
        сессия,
        отпечаток_закрытия,
    ):
        raise ОшибкаОтчёта("снимок не совпадает с фактическими записями")
    if байты != канонические_машинные_байты(значение):
        raise ОшибкаОтчёта("снимок имеет неканонические байты")
    return байты, отпечаток_закрытия


def проверить_закрытое_состояние(
    путь_отчёта: Path,
    путь_снимка: Path,
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
    сессия: str,
) -> None:
    if any(запись["состояние"] == "выполняется" for _, запись, _ in записи):
        raise ОшибкаОтчёта("закрытый снимок содержит выполняющуюся запись")
    байты_снимка, отпечаток_закрытия = проверить_снимок(
        путь_снимка,
        записи,
        сессия,
    )
    маркер = сформировать_закрытый_маркер(байты_снимка)
    текст = путь_отчёта.read_bytes().decode("utf-8")
    начало, конец, фактический_маркер = границы_управляемого_блока(текст)
    if фактический_маркер != маркер:
        raise ОшибкаОтчёта("marker отчёта не совпадает с хэшем снимка")
    ожидаемый_блок = сформировать_блок(
        записи,
        маркер,
        отпечаток_закрытия,
    )
    if текст[начало:конец] != ожидаемый_блок:
        raise ОшибкаОтчёта("Markdown-блок не совпадает с машинным снимком")


def сформировать_закрытый_маркер(байты_снимка: bytes) -> str:
    return (
        "<!-- FUM-CHECK-RUNS:BEGIN состояние=закрыт; "
        "снимок=материалы/запуски-проверок/снимок.json; "
        f"sha256=sha256:{хэш_содержимого(байты_снимка)} -->"
    )


def ожидаемый_журнал_возобновления(
    сессия: str,
    байты_снимка: bytes,
    закрытые_байты_отчёта: bytes,
    открытые_байты_отчёта: bytes,
    отпечаток_закрытия: str | None = None,
) -> dict[str, str]:
    значение = {
        "схема": (
            СХЕМА_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ_С_ВЕРДИКТОМ
            if отпечаток_закрытия is not None
            else СХЕМА_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ
        ),
        "сессия": сессия,
        "хэш_закрытого_отчёта": хэш_содержимого(закрытые_байты_отчёта),
        "хэш_открытого_отчёта": хэш_содержимого(открытые_байты_отчёта),
        "хэш_снимка": хэш_содержимого(байты_снимка),
    }
    if отпечаток_закрытия is not None:
        значение["отпечаток_закрытия"] = отпечаток_закрытия
    return значение


def проверить_журнал_возобновления(
    путь_журнала: Path,
    путь_отчёта: Path,
    путь_снимка: Path,
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
    сессия: str,
) -> tuple[bytes, bytes, bytes, str, bytes, str | None]:
    if any(запись["состояние"] == "выполняется" for _, запись, _ in записи):
        raise ОшибкаОтчёта(
            "журнал возобновления не допускает выполняющуюся запись"
        )
    значение, байты_журнала = прочитать_машинную_запись(путь_журнала)
    if not isinstance(значение, dict):
        raise ОшибкаОтчёта("журнал возобновления содержит неверный набор полей")
    схема = значение.get("схема")
    if схема == СХЕМА_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ:
        ожидаемые_поля = ПОЛЯ_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ
        отпечаток_закрытия = None
    elif схема == СХЕМА_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ_С_ВЕРДИКТОМ:
        ожидаемые_поля = ПОЛЯ_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ_С_ВЕРДИКТОМ
        отпечаток_закрытия = значение.get("отпечаток_закрытия")
        if not isinstance(отпечаток_закрытия, str) or re.fullmatch(
            r"sha256:[0-9a-f]{64}", отпечаток_закрытия
        ) is None:
            raise ОшибкаОтчёта(
                "журнал возобновления содержит неверный отпечаток закрытия"
            )
    else:
        raise ОшибкаОтчёта("журнал возобновления имеет неверную схему")
    if set(значение) != ожидаемые_поля:
        raise ОшибкаОтчёта("журнал возобновления содержит неверный набор полей")
    if значение["сессия"] != сессия:
        raise ОшибкаОтчёта("журнал возобновления принадлежит другой сессии")
    поля_хэшей = (
        "хэш_закрытого_отчёта",
        "хэш_открытого_отчёта",
        "хэш_снимка",
    )
    if any(
        not isinstance(значение[поле], str)
        or re.fullmatch(r"[0-9a-f]{64}", значение[поле]) is None
        for поле in поля_хэшей
    ):
        raise ОшибкаОтчёта("журнал возобновления содержит неверный хэш")
    if байты_журнала != канонические_машинные_байты(значение):
        raise ОшибкаОтчёта("журнал возобновления имеет неканонические байты")

    байты_снимка = канонические_машинные_байты(
        ожидаемый_снимок(записи, сессия, отпечаток_закрытия)
    )
    try:
        текущие_байты_отчёта = путь_отчёта.read_bytes()
    except OSError as ошибка:
        raise ОшибкаОтчёта(f"не удалось прочитать отчёт: {ошибка}") from ошибка
    закрытые_байты_отчёта = заменить_управляемый_блок_в_байтах(
        текущие_байты_отчёта,
        сформировать_блок(
            записи,
            сформировать_закрытый_маркер(байты_снимка),
            отпечаток_закрытия,
        ),
    )
    открытые_байты_отчёта = заменить_управляемый_блок_в_байтах(
        текущие_байты_отчёта,
        сформировать_блок(
            записи,
            ОТКРЫТЫЙ_МАРКЕР,
            отпечаток_закрытия,
        ),
    )
    ожидаемое_значение = ожидаемый_журнал_возобновления(
        сессия,
        байты_снимка,
        закрытые_байты_отчёта,
        открытые_байты_отчёта,
        отпечаток_закрытия,
    )
    if значение != ожидаемое_значение:
        raise ОшибкаОтчёта(
            "хэши журнала возобновления не совпадают с текущей сессией"
        )
    if текущие_байты_отчёта == закрытые_байты_отчёта:
        состояние_отчёта = "закрыт"
    elif текущие_байты_отчёта == открытые_байты_отчёта:
        состояние_отчёта = "открыт"
    else:
        raise ОшибкаОтчёта(
            "отчёт не совпадает ни с одной фазой журнала возобновления"
        )

    снимок_существует = путь_снимка.exists() or путь_снимка.is_symlink()
    if снимок_существует:
        фактические_байты_снимка, фактический_отпечаток_закрытия = проверить_снимок(
            путь_снимка,
            записи,
            сессия,
        )
        if (
            фактические_байты_снимка != байты_снимка
            or фактический_отпечаток_закрытия != отпечаток_закрытия
        ):
            raise ОшибкаОтчёта(
                "снимок не совпадает с журналом возобновления"
            )
    elif состояние_отчёта != "открыт":
        raise ОшибкаОтчёта(
            "закрытая фаза журнала возобновления потеряла снимок"
        )
    return (
        закрытые_байты_отчёта,
        открытые_байты_отчёта,
        байты_снимка,
        состояние_отчёта,
        байты_журнала,
        отпечаток_закрытия,
    )


def проверить_журнал_сессии(
    корень_репозитория: str | Path,
    запрос: str | Path,
) -> list[str]:
    try:
        (
            корень,
            _,
            путь_отчёта,
            каталог,
            сессия,
        ) = разрешить_сессию(корень_репозитория, запрос)
        with межпроцессная_блокировка(корень, сессия):
            запретить_действие_при_возобновлении(каталог, "проверка")
            записи = прочитать_записи(каталог, сессия)
            путь_снимка = каталог / ИМЯ_СНИМКА
            текст = путь_отчёта.read_bytes().decode("utf-8")
            _, _, маркер = границы_управляемого_блока(текст)
            if путь_снимка.exists():
                проверить_закрытое_состояние(
                    путь_отчёта,
                    путь_снимка,
                    записи,
                    сессия,
                )
            else:
                if маркер != ОТКРЫТЫЙ_МАРКЕР:
                    raise ОшибкаОтчёта(
                        "открытый журнал имеет закрытый marker без снимка"
                    )
                if not any(
                    запись["состояние"] == "выполняется"
                    for _, запись, _ in записи
                ):
                    raise ОшибкаОтчёта(
                        "открытый журнал допустим только при выполняющейся записи"
                    )
    except (ОшибкаОтчёта, OSError, UnicodeError) as ошибка:
        return [str(ошибка)]
    return []


def выполнить_предпросмотр(корень_репозитория: Path, запрос: Path) -> int:
    корень, _, путь_отчёта, каталог, сессия = разрешить_сессию(
        корень_репозитория,
        запрос,
    )
    with межпроцессная_блокировка(корень, сессия):
        запретить_действие_при_возобновлении(каталог, "предпросмотр")
        if (каталог / ИМЯ_СНИМКА).exists():
            raise ОшибкаОтчёта("закрытый отчёт нельзя обновить предпросмотром")
        текст = путь_отчёта.read_bytes().decode("utf-8")
        _, _, маркер = границы_управляемого_блока(текст)
        if маркер != ОТКРЫТЫЙ_МАРКЕР:
            raise ОшибкаОтчёта(
                "предпросмотр запрещён для закрытого marker без снимка"
            )
        записи = прочитать_записи(каталог, сессия)
        текущий_отпечаток = (
            вычислить_отпечаток_снимка(корень, Path(сессия).parent)
            if any(
                профиль_записи(запись) is not None
                for _, запись, _ in записи
            )
            else None
        )
        заменить_управляемый_блок(
            путь_отчёта,
            сформировать_блок(
                записи,
                ОТКРЫТЫЙ_МАРКЕР,
                текущий_отпечаток,
            ),
        )
    return 0


def выполнить_проверку_плана(корень_репозитория: Path, запрос: Path) -> int:
    корень, _, путь_отчёта, каталог, сессия = разрешить_сессию(
        корень_репозитория,
        запрос,
    )
    with межпроцессная_блокировка(корень, сессия):
        запретить_действие_при_возобновлении(каталог, "проверка плана")
        путь_снимка = каталог / ИМЯ_СНИМКА
        if путь_снимка.exists() or путь_снимка.is_symlink():
            raise ОшибкаОтчёта("проверить план можно только в открытой сессии")
        текст = путь_отчёта.read_bytes().decode("utf-8")
        _, _, маркер = границы_управляемого_блока(текст)
        if маркер != ОТКРЫТЫЙ_МАРКЕР:
            raise ОшибкаОтчёта("проверить план можно только в открытой сессии")
        записи = прочитать_записи(каталог, сессия)
        if not any(профиль_записи(запись) is not None for _, запись, _ in записи):
            raise ОшибкаОтчёта("машинный журнал не содержит v3-профилей")
        текущий_отпечаток = вычислить_отпечаток_снимка(
            корень,
            Path(сессия).parent,
        )
        проверить_порядок_проверок(записи, текущий_отпечаток)
    print("экономный план проверок подтверждён")
    return 0


def выполнить_закрытие(корень_репозитория: Path, запрос: Path) -> int:
    корень, _, путь_отчёта, каталог, сессия = разрешить_сессию(
        корень_репозитория,
        запрос,
    )
    with межпроцессная_блокировка(корень, сессия):
        запретить_действие_при_возобновлении(каталог, "закрытие")
        записи = прочитать_записи(каталог, сессия)
        путь_снимка = каталог / ИМЯ_СНИМКА
        if путь_снимка.exists():
            if any(
                запись["состояние"] == "выполняется"
                for _, запись, _ in записи
            ):
                raise ОшибкаОтчёта(
                    "подготовленный снимок содержит выполняющуюся запись"
                )
            байты_снимка, отпечаток_закрытия = проверить_снимок(
                путь_снимка,
                записи,
                сессия,
            )
            ожидаемый_маркер = сформировать_закрытый_маркер(байты_снимка)
            текст = путь_отчёта.read_bytes().decode("utf-8")
            _, _, фактический_маркер = границы_управляемого_блока(текст)
            if фактический_маркер == ОТКРЫТЫЙ_МАРКЕР:
                заменить_управляемый_блок(
                    путь_отчёта,
                    сформировать_блок(
                        записи,
                        ожидаемый_маркер,
                        отпечаток_закрытия,
                    ),
                )
            elif фактический_маркер != ожидаемый_маркер:
                raise ОшибкаОтчёта(
                    "закрытый marker не совпадает с подготовленным снимком"
                )
            проверить_закрытое_состояние(
                путь_отчёта,
                путь_снимка,
                записи,
                сессия,
            )
            return 0
        if any(запись["состояние"] == "выполняется" for _, запись, _ in записи):
            raise ОшибкаОтчёта("нельзя закрыть журнал с выполняющейся записью")
        отпечаток_закрытия = (
            вычислить_отпечаток_снимка(корень, Path(сессия).parent)
            if any(
                профиль_записи(запись) is not None
                for _, запись, _ in записи
            )
            else None
        )
        снимок = ожидаемый_снимок(
            записи,
            сессия,
            отпечаток_закрытия,
        )
        байты_снимка = канонические_машинные_байты(снимок)
        маркер = сформировать_закрытый_маркер(байты_снимка)
        атомарно_записать_байты(путь_снимка, байты_снимка)
        заменить_управляемый_блок(
            путь_отчёта,
            сформировать_блок(записи, маркер, отпечаток_закрытия),
        )
        проверить_закрытое_состояние(
            путь_отчёта,
            путь_снимка,
            записи,
            сессия,
        )
    return 0


def выполнить_возобновление(корень_репозитория: Path, запрос: Path) -> int:
    корень, _, путь_отчёта, каталог, сессия = разрешить_сессию(
        корень_репозитория,
        запрос,
    )
    with межпроцессная_блокировка(корень, сессия):
        записи = прочитать_записи(каталог, сессия)
        путь_снимка = каталог / ИМЯ_СНИМКА
        путь_журнала = каталог / ИМЯ_ЖУРНАЛА_ВОЗОБНОВЛЕНИЯ
        if журнал_возобновления_существует(каталог):
            (
                _закрытые_байты_отчёта,
                открытые_байты_отчёта,
                _байты_снимка,
                состояние_отчёта,
                байты_журнала,
                отпечаток_закрытия,
            ) = проверить_журнал_возобновления(
                путь_журнала,
                путь_отчёта,
                путь_снимка,
                записи,
                сессия,
            )
        else:
            if not путь_снимка.exists():
                raise ОшибкаОтчёта("возобновить можно только закрытый снимок")
            проверить_закрытое_состояние(
                путь_отчёта,
                путь_снимка,
                записи,
                сессия,
            )
            байты_снимка, отпечаток_закрытия = проверить_снимок(
                путь_снимка,
                записи,
                сессия,
            )
            if any(
                запись.get("схема") == СХЕМА_ЗАПУСКА_С_НАБЛЮДЕНИЯМИ
                for _, запись, _ in записи
            ):
                raise ОшибкаОтчёта(
                    "исторический снимок v2 нельзя возобновить в контуре v3"
                )
            if (
                отпечаток_закрытия is not None
                and построить_план_успешной_сессии(
                    записи,
                    отпечаток_закрытия,
                )["состояние"]
                == "готов"
            ):
                raise ОшибкаОтчёта(
                    "готовый профилированный снимок нельзя возобновить"
                )
            закрытые_байты_отчёта = путь_отчёта.read_bytes()
            открытые_байты_отчёта = заменить_управляемый_блок_в_байтах(
                закрытые_байты_отчёта,
                сформировать_блок(
                    записи,
                    ОТКРЫТЫЙ_МАРКЕР,
                    отпечаток_закрытия,
                ),
            )
            значение_журнала = ожидаемый_журнал_возобновления(
                сессия,
                байты_снимка,
                закрытые_байты_отчёта,
                открытые_байты_отчёта,
                отпечаток_закрытия,
            )
            байты_журнала = канонические_машинные_байты(значение_журнала)
            атомарно_записать_байты(путь_журнала, байты_журнала)
            состояние_отчёта = "закрыт"

        if состояние_отчёта == "закрыт":
            try:
                заменить_управляемый_блок(
                    путь_отчёта,
                    сформировать_блок(
                        записи,
                        ОТКРЫТЫЙ_МАРКЕР,
                        отпечаток_закрытия,
                    ),
                )
            except ОшибкаОтчёта as ошибка:
                raise ОшибкаОтчёта(
                    "не удалось открыть отчёт; устойчивый журнал возобновления "
                    f"сохранён для повтора: {ошибка}"
                ) from ошибка
        else:
            атомарно_записать_байты(
                путь_отчёта,
                открытые_байты_отчёта,
            )

        if путь_отчёта.read_bytes() != открытые_байты_отчёта:
            raise ОшибкаОтчёта(
                "открытый отчёт не совпадает с журналом возобновления"
            )
        if путь_снимка.exists() or путь_снимка.is_symlink():
            try:
                путь_снимка.unlink()
            except OSError as ошибка:
                raise ОшибкаОтчёта(
                    "не удалось удалить снимок; журнал возобновления "
                    f"сохранён для повтора: {ошибка}"
                ) from ошибка
        try:
            синхронизировать_каталог(каталог)
        except OSError as ошибка:
            raise ОшибкаОтчёта(
                "не удалось подтвердить отсутствие снимка; журнал "
                f"возобновления сохранён для повтора: {ошибка}"
            ) from ошибка
        if путь_снимка.exists() or путь_снимка.is_symlink():
            raise ОшибкаОтчёта(
                "снимок остался после подтверждения фазы возобновления"
            )

        try:
            путь_журнала.unlink()
            синхронизировать_каталог(каталог)
        except OSError as ошибка:
            ошибка_восстановления: ОшибкаОтчёта | None = None
            if not журнал_возобновления_существует(каталог):
                try:
                    атомарно_записать_байты(путь_журнала, байты_журнала)
                except ОшибкаОтчёта as сбой:
                    ошибка_восстановления = сбой
            if журнал_возобновления_существует(каталог):
                raise ОшибкаОтчёта(
                    "не удалось устойчиво удалить журнал возобновления; "
                    f"он восстановлен для повтора: {ошибка}"
                ) from ошибка
            raise ОшибкаОтчёта(
                "не удалось подтвердить или восстановить последний marker "
                "возобновления после готового открытого состояния: "
                f"{ошибка_восстановления or ошибка}"
            ) from ошибка
    return 0


def группа_процессов_существует(идентификатор_группы: int) -> bool:
    try:
        os.killpg(идентификатор_группы, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def дождаться_исчезновения_группы(
    процесс: subprocess.Popen[bytes],
    идентификатор_группы: int,
    предел_секунд: float,
) -> bool:
    предел = time.monotonic() + предел_секунд
    while True:
        процесс.poll()
        if not группа_процессов_существует(идентификатор_группы):
            return True
        остаток = предел - time.monotonic()
        if остаток <= 0:
            return False
        time.sleep(min(ИНТЕРВАЛ_ПРОВЕРКИ_ГРУППЫ, остаток))


def остановить_группу(
    процесс: subprocess.Popen[bytes],
    идентификатор_группы: int,
) -> bool:
    применено_принудительное_завершение = False
    if идентификатор_группы <= 0:
        raise ОшибкаОтчёта("неверный идентификатор дочерней группы процессов")
    try:
        os.killpg(идентификатор_группы, signal.SIGTERM)
    except ProcessLookupError:
        pass
    except PermissionError as ошибка:
        raise ОшибкаОтчёта(
            "не удалось отправить SIGTERM дочерней группе процессов"
        ) from ошибка
    if not дождаться_исчезновения_группы(
        процесс,
        идентификатор_группы,
        ПАУЗА_ПЕРЕД_ПРИНУДИТЕЛЬНОЙ_ОСТАНОВКОЙ,
    ):
        try:
            os.killpg(идентификатор_группы, signal.SIGKILL)
        except ProcessLookupError:
            pass
        except PermissionError as ошибка:
            raise ОшибкаОтчёта(
                "не удалось отправить SIGKILL дочерней группе процессов"
            ) from ошибка
        else:
            применено_принудительное_завершение = True
    try:
        процесс.wait(timeout=ПРЕДЕЛ_ПОДТВЕРЖДЕНИЯ_ОСТАНОВКИ_ГРУППЫ)
    except subprocess.TimeoutExpired as ошибка:
        raise ОшибкаОтчёта(
            "лидер дочерней группы не завершился в отведённый срок"
        ) from ошибка
    if not дождаться_исчезновения_группы(
        процесс,
        идентификатор_группы,
        ПРЕДЕЛ_ПОДТВЕРЖДЕНИЯ_ОСТАНОВКИ_ГРУППЫ,
    ):
        raise ОшибкаОтчёта(
            "дочерняя группа процессов не исчезла в отведённый срок"
        )
    return применено_принудительное_завершение


def имя_сигнала(номер: int) -> str:
    try:
        return signal.Signals(номер).name
    except ValueError:
        return f"сигнал {номер}"


def проверить_ссылку_диагностики_на_отказ(
    профиль: dict[str, object],
    записи: Sequence[tuple[Path, dict[str, object], bytes]],
) -> None:
    if профиль["класс"] != "диагностическая" or профиль[
        "основание"
    ] != "локализация_наблюдаемого_отказа":
        return
    идентификатор = профиль["идентификатор_отказа"]
    совпадения = [
        запись
        for _, запись, _ in записи
        if запись.get("идентификатор") == идентификатор
    ]
    if len(совпадения) != 1:
        raise ОшибкаОтчёта("диагностика ссылается на отсутствующий отказ")
    отказ = совпадения[0]
    профиль_отказа = профиль_записи(отказ)
    if (
        отказ.get("состояние") != "завершён"
        or отказ.get("статус") != "неуспешно"
        or профиль_отказа is None
        or профиль_отказа["отпечаток_снимка"]
        != профиль["отпечаток_снимка"]
    ):
        raise ОшибкаОтчёта("диагностика требует предшествующий отказ на том же снимке")


def выполнить_запуск(
    корень_репозитория: Path,
    запрос: Path,
    название: str,
    исполнитель: str,
    идентификатор_запуска: str | None,
    тайм_аут: float | None,
    команда: Sequence[str],
    класс_проверки: str | None = None,
    полные_наборы: Sequence[str] = (),
    основание: str | None = None,
    идентификатор_отказа: str | None = None,
    ожидаемое_свидетельство: str | None = None,
) -> int:
    корень, _, путь_отчёта, каталог, сессия = разрешить_сессию(
        корень_репозитория,
        запрос,
    )
    проверить_строку(название, "название")
    проверить_строку(исполнитель, "исполнитель")
    if not команда:
        raise ОшибкаОтчёта("после -- должна быть указана команда")
    if any(not isinstance(аргумент, str) or "\0" in аргумент for аргумент in команда):
        raise ОшибкаОтчёта("команда содержит недопустимый аргумент")
    if тайм_аут is not None and (
        not math.isfinite(тайм_аут) or тайм_аут <= 0
    ):
        raise ОшибкаОтчёта("тайм-аут должен быть положительным числом")
    идентификатор = проверить_идентификатор(
        идентификатор_запуска or str(uuid.uuid4())
    )
    запуск_полной_проверки = является_запуском_полной_проверки(корень, команда)
    if класс_проверки is None:
        raise ОшибкаОтчёта("каждый новый запуск требует --класс-проверки")
    if (класс_проверки == "полная") != запуск_полной_проверки:
        raise ОшибкаОтчёта("класс «полная» допустим только для exact run-smoke-check")
    заготовка_профиля: dict[str, object] = {
        "класс": класс_проверки,
        "отпечаток_снимка": "sha256:" + "0" * 64,
        "полные_наборы": list(полные_наборы),
        "основание": основание,
        "идентификатор_отказа": идентификатор_отказа,
        "ожидаемое_свидетельство": ожидаемое_свидетельство,
    }
    проверить_профиль_проверки(
        заготовка_профиля, None, [], "выполняется"
    )
    временный_каталог_наблюдений: tempfile.TemporaryDirectory[str] | None = None
    путь_наблюдений: Path | None = None
    if запуск_полной_проверки:
        временный_каталог_наблюдений = tempfile.TemporaryDirectory(
            prefix="fum-smoke-observations-"
        )
        путь_наблюдений = (
            Path(временный_каталог_наблюдений.name) / "наблюдения.json"
        )
    управляемые_сигналы = {signal.SIGINT, signal.SIGTERM}
    есть_потоковая_маска = hasattr(signal, "pthread_sigmask")
    прежняя_маска: set[signal.Signals] | None = None
    if есть_потоковая_маска:
        прежняя_маска = signal.pthread_sigmask(
            signal.SIG_BLOCK,
            управляемые_сигналы,
        )
    полученный_сигнал: int | None = None
    учтённые_ожидающие_сигналы: set[signal.Signals] = set()
    идёт_очистка = False

    def принять_сигнал(номер_сигнала: int, _кадр: object) -> None:
        nonlocal полученный_сигнал
        if полученный_сигнал is None:
            полученный_сигнал = номер_сигнала
        if not идёт_очистка:
            raise ПрерываниеОбёртки(номер_сигнала)

    прежние_обработчики: dict[int, object] = {}

    def восстановить_рабочую_маску() -> None:
        if прежняя_маска is not None:
            signal.pthread_sigmask(signal.SIG_SETMASK, прежняя_маска)

    def восстановить_маску_дочернего_процесса() -> None:
        if прежняя_маска is not None:
            signal.pthread_sigmask(signal.SIG_SETMASK, прежняя_маска)

    def заблокировать_управляемые_сигналы() -> None:
        if есть_потоковая_маска:
            signal.pthread_sigmask(signal.SIG_BLOCK, управляемые_сигналы)

    def определить_отложенный_сигнал() -> int | None:
        nonlocal полученный_сигнал
        if есть_потоковая_маска and hasattr(signal, "sigpending"):
            ожидающие = set(signal.sigpending()) & управляемые_сигналы
            учтённые_ожидающие_сигналы.update(ожидающие)
            if ожидающие and полученный_сигнал is None:
                полученный_сигнал = int(min(ожидающие, key=int))
        return полученный_сигнал

    def поглотить_учтённые_сигналы() -> None:
        if not (
            есть_потоковая_маска
            and hasattr(signal, "sigpending")
            and hasattr(signal, "sigwait")
        ):
            return
        ожидающие = (
            set(signal.sigpending())
            & учтённые_ожидающие_сигналы
        )
        for номер_сигнала in sorted(ожидающие, key=int):
            signal.sigwait({номер_сигнала})

    try:
        if путь_наблюдений is not None:
            атомарно_записать_байты(
                путь_наблюдений,
                канонические_машинные_байты(
                    начальный_конверт_наблюдений(идентификатор)
                ),
            )
        for номер_сигнала in управляемые_сигналы:
            прежние_обработчики[номер_сигнала] = signal.getsignal(номер_сигнала)
            signal.signal(номер_сигнала, принять_сигнал)

        with межпроцессная_блокировка(корень, сессия):
            каталог.mkdir(parents=True, exist_ok=True)
            if каталог.is_symlink() or not каталог.is_dir():
                raise ОшибкаОтчёта("каталог запусков имеет неверный тип")
            запретить_действие_при_возобновлении(каталог, "новый запуск")
            if (каталог / ИМЯ_СНИМКА).exists():
                raise ОшибкаОтчёта(
                    "после подготовки или закрытия снимка новые запуски запрещены"
                )
            текст_отчёта = путь_отчёта.read_bytes().decode("utf-8")
            _, _, маркер_отчёта = границы_управляемого_блока(текст_отчёта)
            if маркер_отчёта != ОТКРЫТЫЙ_МАРКЕР:
                raise ОшибкаОтчёта(
                    "новый запуск запрещён для закрытого marker без снимка"
                )
            существующие: list[tuple[Path, dict[str, object], bytes]] = []
            if any(каталог.iterdir()):
                существующие = прочитать_записи(каталог, сессия)
            if история_схем_несовместима(
                [запись for _, запись, _ in существующие]
            ):
                raise ОшибкаОтчёта(
                    "новый запуск запрещён после исторической записи в v3-хвосте"
                )
            if any(
                запись.get("схема") == СХЕМА_ЗАПУСКА_С_НАБЛЮДЕНИЯМИ
                for _, запись, _ in существующие
            ):
                raise ОшибкаОтчёта(
                    "историческую v2-сессию нельзя смешивать с новым v3-контуром"
                )
            выполняющиеся = [
                запись
                for _, запись, _ in существующие
                if запись.get("состояние") == "выполняется"
            ]
            if any(
                (профиль_записи(запись) or {}).get("класс") == "полная"
                for запись in выполняющиеся
            ):
                raise ОшибкаОтчёта(
                    "новый запуск запрещён, пока выполняется финальная полная проверка"
                )
            if запуск_полной_проверки and выполняющиеся:
                raise ОшибкаОтчёта(
                    "финальная полная проверка запрещена при выполняющейся записи"
                )
            if идентификатор in {
                str(запись["идентификатор"])
                for _, запись, _ in существующие
            }:
                raise ОшибкаОтчёта("UUID запуска уже существует")
            порядок = max(
                (int(запись["порядок"]) for _, запись, _ in существующие),
                default=0,
            ) + 1
            путь_записи = каталог / f"{порядок}_{идентификатор}.json"
            профиль_проверки = dict(заготовка_профиля)
            профиль_проверки["отпечаток_снимка"] = (
                вычислить_отпечаток_снимка(корень, Path(сессия).parent)
            )
            проверить_ссылку_диагностики_на_отказ(
                профиль_проверки, существующие
            )
            активная_запись: dict[str, object] = {
                "схема": СХЕМА_ПРОФИЛИРОВАННОГО_ЗАПУСКА,
                "идентификатор": идентификатор,
                "сессия": сессия,
                "порядок": порядок,
                "исполнитель": исполнитель,
                "вызов": название,
                "состояние": "выполняется",
                "длительность_наносекунды": None,
                "статус": None,
                "код_завершения": None,
                "пояснение": None,
            }
            активная_запись["план"] = None
            активная_запись["наблюдения"] = []
            активная_запись["профиль_проверки"] = профиль_проверки
            проверить_запись(активная_запись, путь_записи.name, сессия)
            атомарно_записать_байты(
                путь_записи,
                канонические_машинные_байты(активная_запись),
            )

        начало = time.monotonic_ns()
        процесс: subprocess.Popen[bytes] | None = None
        идентификатор_группы: int | None = None
        процесс_запущен = False
        статус: str
        код: int
        пояснение: str | None = None
        возвращаемый_код: int
        try:
            try:
                try:
                    окружение = None
                    if путь_наблюдений is not None:
                        окружение = os.environ.copy()
                        окружение[ПЕРЕМЕННАЯ_ПУТИ_НАБЛЮДЕНИЙ] = str(
                            путь_наблюдений
                        )
                        окружение[ПЕРЕМЕННАЯ_ИДЕНТИФИКАТОРА_ЗАПУСКА] = (
                            идентификатор
                        )
                    процесс = subprocess.Popen(
                        list(команда),
                        cwd=корень,
                        env=окружение,
                        start_new_session=True,
                        preexec_fn=(
                            восстановить_маску_дочернего_процесса
                            if есть_потоковая_маска
                            else None
                        ),
                    )
                    идентификатор_группы = процесс.pid
                    процесс_запущен = True
                finally:
                    восстановить_рабочую_маску()
                код = процесс.wait(timeout=тайм_аут)
                if код == 0:
                    статус = "успешно"
                    возвращаемый_код = 0
                elif код > 0:
                    статус = "неуспешно"
                    возвращаемый_код = код
                else:
                    статус = "прервано"
                    пояснение = имя_сигнала(-код)
                    возвращаемый_код = 128 + (-код)
            except subprocess.TimeoutExpired:
                идёт_очистка = True
                if процесс is not None and идентификатор_группы is not None:
                    применено_принудительное_завершение = остановить_группу(
                        процесс,
                        идентификатор_группы,
                    )
                else:
                    применено_принудительное_завершение = False
                if полученный_сигнал is not None:
                    код = -полученный_сигнал
                    статус = "прервано"
                    пояснение = имя_сигнала(полученный_сигнал)
                    возвращаемый_код = 128 + полученный_сигнал
                else:
                    статус = "не завершено"
                    код = КОД_ТАЙМ_АУТА
                    пояснение = "тайм-аут"
                    if применено_принудительное_завершение:
                        пояснение += "; применён SIGKILL"
                    возвращаемый_код = КОД_ТАЙМ_АУТА
            except FileNotFoundError:
                код = КОД_ОТСУТСТВУЮЩЕЙ_КОМАНДЫ
                статус = "не завершено"
                пояснение = "исполняемый файл не найден"
                возвращаемый_код = КОД_ОТСУТСТВУЮЩЕЙ_КОМАНДЫ
            except PermissionError:
                код = КОД_ОШИБКИ_ДОСТУПА
                статус = "не завершено"
                пояснение = "исполняемый файл недоступен"
                возвращаемый_код = КОД_ОШИБКИ_ДОСТУПА
            except OSError:
                код = КОД_ОШИБКИ_ОБЁРТКИ
                статус = "не завершено"
                пояснение = "системная ошибка запуска"
                возвращаемый_код = КОД_ОШИБКИ_ОБЁРТКИ
            идёт_очистка = True
        except ПрерываниеОбёртки as прерывание:
            идёт_очистка = True
            if процесс is not None and идентификатор_группы is not None:
                остановить_группу(процесс, идентификатор_группы)
            номер_сигнала = полученный_сигнал or прерывание.номер_сигнала
            код = -номер_сигнала
            статус = "прервано"
            пояснение = имя_сигнала(номер_сигнала)
            возвращаемый_код = 128 + номер_сигнала
        finally:
            идёт_очистка = True
            заблокировать_управляемые_сигналы()

        конец = time.monotonic_ns()
        длительность_запуска = max(0, конец - начало)
        план: list[dict[str, str]] | None = None
        наблюдения: list[dict[str, object]] = []
        текущая_проверка: dict[str, object] | None = None
        ошибка_наблюдений: ОшибкаОтчёта | None = None
        if путь_наблюдений is not None:
            try:
                (план, наблюдения, текущая_проверка) = прочитать_конверт_наблюдений(
                    путь_наблюдений,
                    идентификатор,
                )
            except ОшибкаОтчёта as ошибка:
                ошибка_наблюдений = ошибка
        try:
            with межпроцессная_блокировка(корень, сессия):
                значение, _ = прочитать_машинную_запись(путь_записи)
                if значение != активная_запись:
                    raise ОшибкаОтчёта("активная запись была изменена до завершения")
                if (каталог / ИМЯ_СНИМКА).exists():
                    raise ОшибкаОтчёта("снимок появился до терминальной записи")
                номер_итогового_сигнала = определить_отложенный_сигнал()
                if номер_итогового_сигнала is not None:
                    код = -номер_итогового_сигнала
                    статус = "прервано"
                    пояснение = имя_сигнала(номер_итогового_сигнала)
                    возвращаемый_код = 128 + номер_итогового_сигнала
                if запуск_полной_проверки and ошибка_наблюдений is None:
                    try:
                        if текущая_проверка is not None:
                            начало_текущей = int(
                                текущая_проверка[
                                    "начало_монотонные_наносекунды"
                                ]
                            )
                            if not начало <= начало_текущей <= конец:
                                raise ОшибкаОтчёта(
                                    "начало текущей проверки smoke-check "
                                    "вне интервала внешнего запуска"
                                )
                            if статус == "успешно":
                                raise ОшибкаОтчёта(
                                    "успешный smoke-check оставил текущую проверку"
                                )
                            наблюдения.append(
                                {
                                    "ключ_проверки": текущая_проверка["ключ_проверки"],
                                    "название": текущая_проверка["название"],
                                    "статус": (
                                        "прервано"
                                        if статус == "прервано"
                                        else "не завершено"
                                    ),
                                    "длительность_наносекунды": конец - начало_текущей,
                                }
                            )
                        проверить_согласованность_наблюдений(
                            план,
                            наблюдения,
                            статус,
                            длительность_запуска,
                        )
                    except ОшибкаОтчёта as ошибка:
                        ошибка_наблюдений = ошибка
                if ошибка_наблюдений is not None:
                    план = None
                    наблюдения = []
                    if статус == "прервано":
                        пояснение = (
                            f"{пояснение}; наблюдения отброшены: "
                            f"{ошибка_наблюдений}"
                        )
                    elif процесс_запущен:
                        код = КОД_ОШИБКИ_ОБЁРТКИ
                        статус = "не завершено"
                        пояснение = (
                            "неверные наблюдения smoke-check: "
                            f"{ошибка_наблюдений}"
                        )
                        возвращаемый_код = КОД_ОШИБКИ_ОБЁРТКИ
                завершённая_запись = dict(активная_запись)
                завершённая_запись.update(
                    {
                        "состояние": "завершён",
                        "длительность_наносекунды": длительность_запуска,
                        "статус": статус,
                        "код_завершения": код,
                        "пояснение": пояснение,
                    }
                )
                if запуск_полной_проверки:
                    завершённая_запись["план"] = план
                    завершённая_запись["наблюдения"] = наблюдения
                if профиль_проверки is not None and профиль_проверки["класс"] == "полная":
                    завершённый_профиль = dict(профиль_проверки)
                    завершённый_профиль["полные_наборы"] = (
                        [элемент["ключ_проверки"] for элемент in план]
                        if план is not None
                        else []
                    )
                    завершённая_запись["профиль_проверки"] = завершённый_профиль
                проверить_запись(
                    завершённая_запись,
                    путь_записи.name,
                    сессия,
                )
                атомарно_записать_байты(
                    путь_записи,
                    канонические_машинные_байты(завершённая_запись),
                )
                поглотить_учтённые_сигналы()
        except ОшибкаОтчёта as ошибка:
            print(str(ошибка), file=sys.stderr)
            return КОД_ОШИБКИ_ОБЁРТКИ
        return возвращаемый_код
    finally:
        заблокировать_управляемые_сигналы()
        for номер_сигнала, прежний in прежние_обработчики.items():
            signal.signal(номер_сигнала, прежний)
        восстановить_рабочую_маску()
        if временный_каталог_наблюдений is not None:
            временный_каталог_наблюдений.cleanup()


def положительное_число(значение: str) -> float:
    try:
        число = float(значение)
    except ValueError as ошибка:
        raise argparse.ArgumentTypeError("ожидается число") from ошибка
    if not math.isfinite(число) or число <= 0:
        raise argparse.ArgumentTypeError("ожидается положительное конечное число")
    return число


def добавить_общие_аргументы(разбор: argparse.ArgumentParser) -> None:
    разбор.add_argument("--корень-репозитория", type=Path, required=True)
    разбор.add_argument("--запрос", type=Path, required=True)


def построить_разбор_аргументов() -> argparse.ArgumentParser:
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    команды = разбор.add_subparsers(dest="подкоманда", required=True)
    for имя in ("предпросмотр", "проверить-план", "закрыть", "возобновить", "проверить"):
        подкоманда = команды.add_parser(имя, allow_abbrev=False)
        добавить_общие_аргументы(подкоманда)
    запуск = команды.add_parser("запустить", allow_abbrev=False)
    добавить_общие_аргументы(запуск)
    запуск.add_argument("--название", required=True)
    запуск.add_argument("--исполнитель", required=True)
    запуск.add_argument("--идентификатор-запуска")
    запуск.add_argument("--тайм-аут-секунды", type=положительное_число)
    запуск.add_argument(
        "--класс-проверки",
        choices=sorted(КЛАССЫ_ПРОВЕРОК),
        required=True,
    )
    запуск.add_argument("--полный-набор", action="append", default=[])
    запуск.add_argument("--основание", choices=sorted(ОСНОВАНИЯ_ДИАГНОСТИКИ))
    запуск.add_argument("--идентификатор-отказа")
    запуск.add_argument("--ожидаемое-свидетельство")
    запуск.add_argument("аргументы_команды", nargs=argparse.REMAINDER)
    return разбор


def главная(аргументы: Sequence[str] | None = None) -> int:
    пространство = построить_разбор_аргументов().parse_args(аргументы)
    try:
        if пространство.подкоманда == "запустить":
            команда = list(пространство.аргументы_команды)
            if not команда or команда[0] != "--":
                raise ОшибкаОтчёта("команда должна быть указана после --")
            команда = команда[1:]
            return выполнить_запуск(
                пространство.корень_репозитория,
                пространство.запрос,
                пространство.название,
                пространство.исполнитель,
                пространство.идентификатор_запуска,
                пространство.тайм_аут_секунды,
                команда,
                пространство.класс_проверки,
                пространство.полный_набор,
                пространство.основание,
                пространство.идентификатор_отказа,
                пространство.ожидаемое_свидетельство,
            )
        if пространство.подкоманда == "предпросмотр":
            return выполнить_предпросмотр(
                пространство.корень_репозитория,
                пространство.запрос,
            )
        if пространство.подкоманда == "проверить-план":
            return выполнить_проверку_плана(
                пространство.корень_репозитория,
                пространство.запрос,
            )
        if пространство.подкоманда == "закрыть":
            return выполнить_закрытие(
                пространство.корень_репозитория,
                пространство.запрос,
            )
        if пространство.подкоманда == "возобновить":
            return выполнить_возобновление(
                пространство.корень_репозитория,
                пространство.запрос,
            )
        ошибки = проверить_журнал_сессии(
            пространство.корень_репозитория,
            пространство.запрос,
        )
        if ошибки:
            raise ОшибкаОтчёта("; ".join(ошибки))
        print("проверка отчёта о запусках проверок пройдена")
        return 0
    except ОшибкаОтчёта as ошибка:
        print(str(ошибка), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(главная())

#!/usr/bin/env python3
"""Проверить закрытые v3-свидетельства неизменяемого коммита без записи файлов."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import types
from collections.abc import Mapping
from pathlib import Path

import отчёты_о_запусках_проверок as отчёты
from связь_отпечатка_с_коммитом import (
    выполнить_чтение_репозитория,
    пути_границы,
    связать_отпечаток_с_коммитом,
    связать_отпечаток_со_слиянием,
)

ОшибкаОтчёта = отчёты.ОшибкаОтчёта


def уникальный_объект(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ОшибкаОтчёта("повторный ключ JSON")
        результат[ключ] = значение
    return результат


def отклонить_константу(значение):
    raise ОшибкаОтчёта("нечисловая константа JSON недопустима")


def разобрать_байты(байты: bytes):
    if not isinstance(байты, bytes):
        raise ОшибкаОтчёта("машинное свидетельство должно быть байтами")
    try:
        return json.loads(байты.decode("utf-8"), object_pairs_hook=уникальный_объект, parse_constant=отклонить_константу)
    except (UnicodeError, ValueError, RecursionError) as ошибка:
        raise ОшибкаОтчёта("не удалось разобрать машинное свидетельство") from ошибка


def папка_запроса(запрос: str) -> str:
    отчёты.проверить_аналитический_ключ(запрос, "запрос")
    путь = Path(запрос)
    if путь.name != "запрос.md" or len(путь.parts) != 3:
        raise ОшибкаОтчёта("нужен точный файл запроса в Журнале")
    папка = путь.parent.as_posix()
    пути_границы(папка)
    return папка


def проверить_байты_закрытого_отчёта(
    запрос: str, байты_отчёта: bytes, файлы_запусков: Mapping[str, bytes],
) -> dict:
    """Проверяет целостность и готовность; не устанавливает смысловую приёмку."""
    папка_запроса(запрос)
    if not isinstance(файлы_запусков, Mapping) or "снимок.json" not in файлы_запусков:
        raise ОшибкаОтчёта("нет полного инвентаря со снимком")
    записи = []
    for имя, байты in файлы_запусков.items():
        if имя == "снимок.json":
            continue
        if not isinstance(имя, str) or отчёты.ИМЯ_ФАЙЛА_ЗАПУСКА.fullmatch(имя) is None:
            raise ОшибкаОтчёта("неизвестный путь в каталоге запусков")
        значение = отчёты.проверить_запись(разобрать_байты(байты), имя, запрос)
        записи.append((Path(имя), значение, байты))
    if not записи:
        raise ОшибкаОтчёта("машинный журнал пуст")
    for ключ in ("порядок", "идентификатор"):
        значения = [запись[ключ] for _, запись, _ in записи]
        if len(set(значения)) != len(значения):
            raise ОшибкаОтчёта("повтор порядка или UUID запуска")
    записи.sort(key=lambda элемент: (элемент[1]["порядок"], элемент[1]["идентификатор"]))
    байты_снимка = файлы_запусков["снимок.json"]
    снимок = разобрать_байты(байты_снимка)
    if not isinstance(снимок, dict) or снимок.get("схема") != отчёты.СХЕМА_СНИМКА_С_ВЕРДИКТОМ:
        raise ОшибкаОтчёта("требуется закрытый снимок профилированных запусков")
    отпечаток = снимок.get("отпечаток_закрытия")
    if снимок != отчёты.ожидаемый_снимок(записи, запрос, отпечаток):
        raise ОшибкаОтчёта("снимок не совпадает с полным инвентарём запусков")
    if байты_снимка != отчёты.канонические_машинные_байты(снимок):
        raise ОшибкаОтчёта("неканонические байты снимка")
    if not isinstance(байты_отчёта, bytes):
        raise ОшибкаОтчёта("отчёт должен быть байтами")
    try:
        текст = байты_отчёта.decode("utf-8")
    except UnicodeError as ошибка:
        raise ОшибкаОтчёта("отчёт не декодируется как UTF-8") from ошибка
    начало, конец, фактический = отчёты.границы_управляемого_блока(текст)
    маркер = отчёты.сформировать_закрытый_маркер(байты_снимка)
    if фактический != маркер or текст[начало:конец] != отчёты.сформировать_блок(записи, маркер, отпечаток):
        raise ОшибкаОтчёта("управляемый блок отчёта не совпадает со снимком")
    отчёты.проверить_порядок_проверок(записи, отпечаток)
    финальная = записи[-1][1]
    return {
        "схема": "fum.проверенный-отчёт.1", "сессия": запрос,
        "состояние": "проверен", "запусков": len(записи),
        "финальный_запуск": финальная["идентификатор"],
        "отпечаток_закрытия": отпечаток,
        "отпечаток_запуска": финальная["профиль_проверки"]["отпечаток_снимка"],
        "sha256_снимка": отчёты.хэш_содержимого(байты_снимка),
        "завершение_обязательства_доказано": False,
    }


def разобрать_пакет_объектов(ожидаемые: list[str], байты: bytes) -> dict[str, bytes]:
    if any(not isinstance(объект, str) or re.fullmatch(r"(?:[0-9a-f]{40}|[0-9a-f]{64})", объект) is None for объект in ожидаемые) or len(set(ожидаемые)) != len(ожидаемые):
        raise ОшибкаОтчёта("пакет требует уникальные полные OID")
    объекты = {}
    позиция = 0
    for объект in ожидаемые:
        конец = байты.find(b"\n", позиция)
        if конец < 0:
            raise ОшибкаОтчёта("неполный заголовок пакетного ответа Git")
        поля = байты[позиция:конец].split(b" ")
        if len(поля) != 3 or поля[0] != объект.encode() or поля[1] != b"blob" or re.fullmatch(rb"(?:0|[1-9][0-9]*)", поля[2]) is None:
            raise ОшибкаОтчёта("неверные OID, тип или размер пакетного объекта")
        try:
            размер = int(поля[2])
        except ValueError as ошибка:
            raise ОшибкаОтчёта("размер пакетного объекта недопустим") from ошибка
        начало = конец + 1
        конец = начало + размер
        if конец >= len(байты) or байты[конец:конец + 1] != b"\n":
            raise ОшибкаОтчёта("неполные байты или разделитель пакетного объекта")
        объекты[объект] = байты[начало:конец]
        позиция = конец + 1
    if позиция != len(байты):
        raise ОшибкаОтчёта("лишний ответ в пакете Git")
    return объекты


def прочитать_свидетельства_коммита(корень: Path, коммит: str, запрос: str) -> tuple[bytes, dict[str, bytes]]:
    папка = папка_запроса(запрос)
    if not isinstance(коммит, str) or re.fullmatch(r"(?:[0-9a-f]{40}|[0-9a-f]{64})", коммит) is None:
        raise ОшибкаОтчёта("нужен полный OID коммита")
    читать = lambda *аргументы: выполнить_чтение_репозитория(корень, *аргументы)
    if Path(читать("rev-parse", "--show-toplevel").decode().rstrip("\n")).resolve() != корень:
        raise ОшибкаОтчёта("переданный корень не совпадает с checkout")
    if читать("rev-parse", "--verify", коммит).strip() != коммит.encode() or читать("cat-file", "-t", коммит).strip() != b"commit":
        raise ОшибкаОтчёта("объект не является точным полным коммитом")
    дерево = читать("ls-tree", "-r", "-t", "-z", "--full-tree", коммит, "--", папка)
    каталог = (Path(папка) / "материалы/запуски-проверок").as_posix() + "/"
    путь_отчёта = str(Path(папка) / "отчёт.md")
    выбранные = {}
    for строка in дерево.split(b"\0"):
        if not строка:
            continue
        метаданные, имя = строка.split(b"\t", 1)
        режим, тип, объект = метаданные.split(b" ")
        имя = имя.decode("utf-8")
        if имя not in {запрос, путь_отчёта, каталог.rstrip("/")} and not имя.startswith(каталог):
            continue
        if имя == каталог.rstrip("/") and режим == b"040000" and тип == b"tree":
            continue
        if режим not in {b"100644", b"100755"} or тип != b"blob":
            raise ОшибкаОтчёта("свидетельство не является обычным файлом в Git")
        if имя in выбранные:
            raise ОшибкаОтчёта("неоднозначный инвентарь дерева Git")
        выбранные[имя] = объект.decode("ascii")
    if запрос not in выбранные or путь_отчёта not in выбранные:
        raise ОшибкаОтчёта("в коммите отсутствует запрос или отчёт")
    ожидаемые = sorted(set(выбранные.values()))
    вход = ("\n".join(ожидаемые) + "\n").encode("ascii")
    пакет = выполнить_чтение_репозитория(корень, "cat-file", "--batch", вход=вход)
    объекты = разобрать_пакет_объектов(ожидаемые, пакет)
    содержимое = {имя: объекты[объект] for имя, объект in выбранные.items()}
    файлы = {имя[len(каталог):]: байты for имя, байты in содержимое.items() if имя.startswith(каталог)}
    return содержимое[путь_отчёта], файлы


def проверить_отчёт_в_коммите(корень_репозитория: str | Path, коммит: str, запрос: str) -> dict:
    корень = Path(корень_репозитория).resolve()
    байты_отчёта, файлы = прочитать_свидетельства_коммита(корень, коммит, запрос)
    результат = проверить_байты_закрытого_отчёта(запрос, байты_отчёта, файлы)
    связь = связать_отпечаток_с_коммитом(корень, папка_запроса(запрос), коммит, результат["отпечаток_закрытия"], результат["отпечаток_запуска"], "исторический")
    return {**результат, "коммит": коммит, "связь": связь, "состояние": "подтверждён" if связь["состояние"] == "подтверждён" else "не подтверждён"}


def проверить_отчёт_в_слиянии(
    корень_репозитория: str | Path,
    коммит: str,
    запрос: str,
    база: str,
    присоединяемый: str,
    дерево: str,
) -> dict:
    """Проверить закрытые байты и связь с [L, M]; это не разрешение продвижения ref."""
    результат, _ = проверить_слияние_и_прочитать_запуски(корень_репозитория, коммит, запрос, база, присоединяемый, дерево)
    return результат


def проверить_слияние_и_прочитать_запуски(корень_репозитория, коммит, запрос, база, присоединяемый, дерево):
    корень = Path(корень_репозитория).resolve()
    байты_отчёта, файлы = прочитать_свидетельства_коммита(корень, коммит, запрос)
    результат = проверить_байты_закрытого_отчёта(запрос, байты_отчёта, файлы)
    связь = связать_отпечаток_со_слиянием(
        корень, папка_запроса(запрос), коммит, база, присоединяемый, дерево,
        результат["отпечаток_закрытия"], результат["отпечаток_запуска"],
    )
    return {**результат, "коммит": коммит, "связь": связь,
            "состояние": "подтверждён" if связь["состояние"] == "подтверждён" else "не подтверждён"}, файлы


def объект_пути(корень: Path, коммит: str, путь: str, режим: bytes, тип: bytes) -> str:
    """Прочитать единственную точную запись неизменяемого дерева."""
    ответ = выполнить_чтение_репозитория(корень, "ls-tree", "-z", "--full-tree", коммит, "--", путь)
    шаблон = re.escape(режим + b" " + тип + b" ") + rb"([0-9a-f]{40}|[0-9a-f]{64})\t" + re.escape(путь.encode("utf-8")) + rb"\x00"
    совпадение = re.fullmatch(шаблон, ответ)
    if совпадение is None:
        raise ОшибкаОтчёта("неверный тип или инвентарь свидетельства: " + путь)
    return совпадение[1].decode("ascii")


def прочитать_обычный_blob(корень: Path, коммит: str, путь: str) -> tuple[str, bytes]:
    объект = объект_пути(корень, коммит, путь, b"100644", b"blob")
    пакет = выполнить_чтение_репозитория(корень, "cat-file", "--batch", вход=(объект + "\n").encode("ascii"))
    return объект, разобрать_пакет_объектов([объект], пакет)[объект]


def проверить_допуск_слияния(
    корень_репозитория: str | Path, коммит: str, запрос: str,
    база: str, присоединяемый: str, дерево: str,
) -> dict:
    """Связать закрытый полный запуск, источник M и точный merge; refs не изменять."""
    результат, файлы = проверить_слияние_и_прочитать_запуски(корень_репозитория, коммит, запрос, база, присоединяемый, дерево)
    корень = Path(корень_репозитория).resolve()
    путь_модуля = "Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts/граница_зависимостей_слияния.py"
    _, байты_модуля = прочитать_обычный_blob(корень, присоединяемый, путь_модуля)
    зависимости = types.ModuleType("граница_зависимостей_принятого_источника")
    # Даже при повторе из частично обновлённого checkout исполняется blob M.
    exec(compile(байты_модуля, путь_модуля, "exec"), зависимости.__dict__)
    зависимости.проверить_объекты(выполнить_чтение_репозитория, корень, присоединяемый, база, коммит)
    путь = (Path(папка_запроса(запрос)) / "материалы" / "контур-слияния.json").as_posix()
    blob, байты = прочитать_обычный_blob(корень, коммит, путь)
    финальная = next(разобрать_байты(содержимое) for имя, содержимое in файлы.items()
                     if имя.endswith("_" + результат["финальный_запуск"] + ".json"))
    подтверждение = "fum.контур-проверки-слияния.1:sha256:" + отчёты.хэш_содержимого(байты)
    if финальная["профиль_проверки"]["ожидаемое_свидетельство"] != подтверждение:
        raise ОшибкаОтчёта("финальный запуск не подтверждает исполнение контура master")
    архив = "Инструменты/fum-proverka-nazvanij-avtomatizacij"
    gitlink = "Зависимости/LinguisticKit"
    политика = "Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/policy-кандидата-слияния.json"
    происхождение = "Инструменты/fum-proverka-mashinno-lokaljnyikh-putej/происхождение-политики-слияния.json"
    обёртка = объект_пути(корень, присоединяемый, архив, b"040000", b"tree")
    for вершина in (база, коммит):
        if объект_пути(корень, вершина, архив, b"040000", b"tree") != обёртка:
            raise ОшибкаОтчёта("архивируемая обёртка L или C отличается от источника M")
    зависимость = объект_пути(корень, присоединяемый, gitlink, b"160000", b"commit")
    if объект_пути(корень, коммит, gitlink, b"160000", b"commit") != зависимость:
        raise ОшибкаОтчёта("gitlink кандидата отличается от проверенной зависимости M")
    _, байты_политики = прочитать_обычный_blob(корень, присоединяемый, политика)
    _, байты_происхождения = прочитать_обычный_blob(корень, присоединяемый, происхождение)
    хэш = "sha256:" + hashlib.sha256(байты_политики).hexdigest()
    описание = разобрать_байты(байты_происхождения)
    дерево_коммита = lambda oid: выполнить_чтение_репозитория(корень, "rev-parse", oid + "^{tree}").decode("ascii").strip()
    if (not isinstance(описание, dict)
            or описание.get("схема") != "fum.политика-слияния.1"
            or описание.get("ведущая_основа") != база
            or описание.get("дерево_основы") != дерево_коммита(база)
            or описание.get("путь_политики") != политика
            or описание.get("хэш_политики") != хэш
            or описание.get("принятие_слияния") is not False):
        raise ОшибкаОтчёта("происхождение политики из M не совпадает с проверяемым слиянием")
    ожидаемое = {
        "схема": "fum.контур-проверки-слияния.1", "источник": присоединяемый,
        "дерево_источника": дерево_коммита(присоединяемый), "ведущая_основа": база,
        "архивируемая_обёртка": обёртка, "зависимость": зависимость, "политика": хэш,
        "запрос": запрос, "идентификатор_запуска": результат["финальный_запуск"],
    }
    канонические = (json.dumps(ожидаемое, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")
    if байты != канонические:
        raise ОшибкаОтчёта("свидетельство не связывает точный источник M с последним полным запуском")
    return {**результат, "происхождение_проверок": {"путь": путь, "blob": blob, **ожидаемое}}


def главная() -> int:
    разбор = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    разбор.add_argument("--корень-репозитория", default=".")
    разбор.add_argument("--коммит", required=True)
    разбор.add_argument("--запрос", required=True)
    режим = разбор.add_mutually_exclusive_group()
    режим.add_argument("--слияние", action="store_true")
    режим.add_argument("--допуск-слияния", action="store_true")
    разбор.add_argument("--база")
    разбор.add_argument("--присоединяемый")
    разбор.add_argument("--дерево")
    параметры = разбор.parse_args()
    значения = vars(параметры).copy()
    слияние = значения.pop("слияние")
    допуск = значения.pop("допуск_слияния")
    границы = {ключ: значения.pop(ключ) for ключ in ("база", "присоединяемый", "дерево")}
    if слияние or допуск:
        if not all(границы.values()):
            разбор.error("слияние требует полные базу, присоединяемый коммит и дерево")
    elif any(значение is not None for значение in границы.values()):
        разбор.error("границы слияния требуют явного --слияние или --допуск-слияния")
    try:
        if допуск:
            итог = проверить_допуск_слияния(**значения, **границы)
        elif слияние:
            итог = проверить_отчёт_в_слиянии(**значения, **границы)
        else:
            итог = проверить_отчёт_в_коммите(**значения)
    except (ОшибкаОтчёта, OSError, ValueError) as ошибка:
        print(f"Ошибка: {ошибка}", file=sys.stderr)
        return 1

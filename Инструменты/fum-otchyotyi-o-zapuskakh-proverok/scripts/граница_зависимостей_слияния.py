"""Общая закрытая граница gitlinks; разрешение читается только из принятого M."""
from __future__ import annotations

import json
import os
from pathlib import PurePosixPath
import re


ПРОФИЛЬ = "Инструменты/fum-otchyotyi-o-zapuskakh-proverok/профиль-зависимостей-слияния.json"
ЯЗЫКОВАЯ_ЗАВИСИМОСТЬ = "Зависимости/LinguisticKit"
ТЕЛЕГРАМ_ЗАВИСИМОСТЬ = "Зависимости/TDLib"
ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА = re.compile(r"[0-9a-f]{40}\Z")
ПОЛЯ = {"схема", "gitmodules_до", "gitmodules_после", "LinguisticKit", "TDLib", "origin", "upstream"}


def уникальный_объект(пары):
    итог = {}
    for ключ, значение in пары:
        if ключ in итог:
            raise ValueError("Повторное поле профиля зависимости")
        итог[ключ] = значение
    return итог


def разобрать_политику(байты):
    значение = json.loads(байты.decode("utf-8"), object_pairs_hook=уникальный_объект)
    if (not isinstance(значение, dict) or set(значение) != ПОЛЯ
            or значение["схема"] != "fum.добавление-TDLib.1"
            or значение["origin"] != "https://github.com/fum-lab/TDLib.git"
            or значение["upstream"] != "https://github.com/tdlib/td.git"):
        raise ValueError("Неизвестный профиль или источник зависимости")
    for поле in ("gitmodules_до", "gitmodules_после", "LinguisticKit", "TDLib"):
        if not isinstance(значение[поле], str) or ШАБЛОН_ИДЕНТИФИКАТОРА_ОБЪЕКТА.fullmatch(значение[поле]) is None:
            raise ValueError("Профиль требует полные закреплённые SHA-1 OID")
    if значение["gitmodules_до"] == значение["gitmodules_после"]:
        raise ValueError("Добавление зависимости должно изменять точный .gitmodules")
    return значение


def часть_зависимостей(дерево):
    return {имя: объект for имя, объект in дерево.items()
            if объект[0] == "160000" or имя == ".gitmodules"}


def проверить_переход(до, ведущая, после, политика):
    """Сопоставить полный инвентарь; обычные файлы проверяет окружающий контур."""
    старые, исходные, новые = map(часть_зависимостей, (до, ведущая, после))
    # Прежний обычный переход сопоставлял M и C: L может предшествовать
    # уже принятой зависимости. Новое добавление отдельно закрепляет L.
    if старые == новые:
        return None
    if политика is None:
        raise ValueError("В M отсутствует закрытое разрешение изменения gitlinks или .gitmodules")
    политика = разобрать_политику(json.dumps(политика, ensure_ascii=False).encode("utf-8"))
    ожидаемые_старые = {
        ".gitmodules": ("100644", политика["gitmodules_до"]),
        ЯЗЫКОВАЯ_ЗАВИСИМОСТЬ: ("160000", политика["LinguisticKit"]),
    }
    ожидаемые_новые = ожидаемые_старые | {
        ".gitmodules": ("100644", политика["gitmodules_после"]),
        ТЕЛЕГРАМ_ЗАВИСИМОСТЬ: ("160000", политика["TDLib"]),
    }
    if старые != ожидаемые_старые or исходные != ожидаемые_новые or новые != ожидаемые_новые:
        raise ValueError("Gitlinks или .gitmodules отличаются от закрытого профиля M/L/C")
    return dict(политика)


def инвентарь(читать, корень, вершина=None):
    """Привести Git-дерево либо весь stage-0 индекс к одной форме."""
    команда = ("ls-files", "--stage", "-z") if вершина is None else ("ls-tree", "-rz", вершина)
    итог = {}
    for запись in читать(корень, *команда).split(b"\0"):
        if not запись:
            continue
        поля, сырое_имя = запись.split(b"\t", 1)
        режим, среднее, третье = поля.decode("ascii").split()
        if вершина is None:
            идентификатор_объекта = среднее
            if третье != "0":
                raise ValueError("Незакрытые стадии индекса зависимостей")
        else:
            идентификатор_объекта = третье
            if (режим == "160000") != (среднее == "commit"):
                raise ValueError("Несовместимые тип и режим Git-объекта")
        имя = os.fsdecode(сырое_имя)
        путь = PurePosixPath(имя)
        if (путь.is_absolute() or путь.as_posix() != имя or ".." in путь.parts
                or имя in итог):
            raise ValueError("Неоднозначный путь в инвентаре зависимостей")
        итог[имя] = (режим, идентификатор_объекта)
    return итог


def прочитать_политику(читать, корень, принимающий):
    запись = читать(корень, "ls-tree", "-z", принимающий, "--", ПРОФИЛЬ)
    if not запись:
        return None
    совпадение = re.fullmatch(rb"100644 blob ([0-9a-f]{40})\t" + re.escape(ПРОФИЛЬ.encode()) + b"\0", запись)
    if совпадение is None:
        raise ValueError("Профиль зависимости M должен быть единственным обычным blob")
    return разобрать_политику(читать(корень, "cat-file", "blob", совпадение[1].decode("ascii")))


def проверить_объекты(читать, корень, принимающий, ведущий, кандидат=None):
    return проверить_переход(
        инвентарь(читать, корень, принимающий), инвентарь(читать, корень, ведущий),
        инвентарь(читать, корень, кандидат), прочитать_политику(читать, корень, принимающий),
    )

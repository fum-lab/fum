        сам.assertEqual(сам.проверить()["состояние"], "подтверждён")
        после = {путь.relative_to(сам.корень): (путь.read_bytes() if путь.is_file() else None, путь.lstat().st_mode) for путь in сам.корень.rglob("*")}
        сам.assertEqual(до, после)


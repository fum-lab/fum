    def test_поздние_байты_и_исполняемый_режим_не_совпадают_с_отпечатком(сам):
        исходный = сам.гит("rev-parse", сам.коммит + ":результат.bin").decode().strip()
        изменённый = сам.гит("hash-object", "-w", "--stdin", вход=b"late bytes").decode().strip()
        for режим, объект in (("100644", изменённый), ("100755", исходный)):
            сам.гит("update-index", "--cacheinfo", f"{режим},{объект},результат.bin")
            дерево = сам.гит("write-tree").decode().strip()
            with сам.subTest(режим=режим):
                итог = сам.проверить(коммит=сам.коммит_дерева(дерево), дерево=дерево)
                сам.assertEqual(итог["состояние"], "не подтверждён")


    def test_согласованное_свидетельство_без_успешной_полной_проверки(сам):
        for тип in ("адресная", "неуспешная"):
            запись = copy.deepcopy(json.loads(сам.файлы[сам.имя]))
            if тип == "адресная":
                запись.update({"план": None, "наблюдения": []})
                запись["профиль_проверки"].update({"класс": "адресная", "полные_наборы": []})
            else:
                запись.update({"статус": "неуспешно", "код_завершения": 1})
                запись["наблюдения"][0]["статус"] = "неуспешно"
            файлы, отчёт = тесты_читателя.ТестыЧтенияЗакрытогоОтчёта.пересобрать(сам, [запись])
            for имя, байты in файлы.items():
                (сам.фикстура.каталог_записей / имя).write_bytes(байты)
            сам.фикстура.отчёт.write_bytes(отчёт)
            сам.гит("add", ".")
            дерево = сам.гит("write-tree").decode().strip()
            with сам.subTest(тип=тип), сам.assertRaises(сам.адаптер.ОшибкаОтчёта):
                сам.проверить(коммит=сам.коммит_дерева(дерево), дерево=дерево)

    def test_чтение_слияния_не_зависит_от_живого_состояния_и_не_пишет(сам):
        сам.фикстура.отчёт.write_bytes(b"broken live report")
        (сам.фикстура.каталог_записей / "снимок.json").unlink()
        (сам.корень / "результат.bin").write_bytes(b"local dirty")
        сам.гит("update-index", "--assume-unchanged", "результат.bin")
        (сам.корень / "новый.txt").write_text("Локальные данные")

class ТестыСвидетельстваСлияния(unittest.TestCase):
    def test_пакет_метаданных_отклоняет_перестановки_обрезание_и_ложные_размеры(сам):
        исходное_чтение = сам.адаптер.выполнить_чтение_репозитория
        вход = ("\n".join((сам.база, сам.присоединяемый, сам.коммит, сам.дерево)) + "\n").encode()
        правильный = исходное_чтение(сам.корень, "cat-file", "--batch-check", вход=вход)
        строки = правильный.splitlines(keepends=True)
        поля = строки[0].split()
        варианты = [правильный[:-1], правильный + строки[0], b"".join((строки[1], строки[0], *строки[2:])),
                    строки[0] + строки[0] + b"".join(строки[2:]), поля[0] + b" missing\n" + b"".join(строки[1:])]
        for размер in (b"-1", b"1.0", b"01", b"+1"):
            варианты.append(поля[0] + b" " + поля[1] + b" " + размер + b"\n" + b"".join(строки[1:]))
        варианты.append(поля[0] + b" tag " + поля[2] + b"\n" + b"".join(строки[1:]))
        for номер, подмена in enumerate(варианты):
            def читать(корень, *аргументы, **ключи):
                if аргументы == ("cat-file", "--batch-check"):
                    return подмена
                return исходное_чтение(корень, *аргументы, **ключи)
            with сам.subTest(номер=номер), mock.patch.object(сам.адаптер, "выполнить_чтение_репозитория", side_effect=читать):
                with сам.assertRaises(сам.адаптер.ОшибкаОтчёта): сам.связать()

    def setUp(сам):
        изоляция = mock.patch.dict(os.environ, {"GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull})
        изоляция.start()
        сам.addCleanup(изоляция.stop)
        sys.path.insert(0, str(сценарии))
        сам.addCleanup(sys.path.remove, str(сценарии))
        сам.адаптер = importlib.import_module("связь_отпечатка_с_коммитом")
        сам.читатель = importlib.import_module("закрытый_отчёт_из_гита")
        сам.создать_слияние()

    def гит(сам, *аргументы, вход=None):
        return subprocess.run(["git", "-C", str(сам.корень), *аргументы], input=вход, check=True, capture_output=True).stdout

    def создать_слияние(сам, формат=None):
        сам.фикстура = ФикстураОтчётов()
        сам.addCleanup(сам.фикстура.очистить)
        сам.корень = сам.фикстура.корень
        if формат:
            shutil.rmtree(сам.корень / ".git")
            сам.гит("init", "-q", "--object-format=" + формат)
            сам.гит("config", "user.name", "FUM Tests")
            сам.гит("config", "user.email", "fum-tests@example.invalid")
            сам.гит("add", ".")
            сам.гит("commit", "-qm", "Исходная фикстура")
        сам.исходная = сам.гит("rev-parse", "HEAD").decode().strip()
        сам.гит("checkout", "-qb", "сторона")
        (сам.корень / "сторона.txt").write_text("Присоединяемый результат.\n")
        сам.гит("add", ".")
        сам.гит("commit", "-qm", "Независимая сторона")
        сам.присоединяемый = сам.гит("rev-parse", "HEAD").decode().strip()
        сам.гит("checkout", "-qb", "приёмка", сам.исходная)
        (сам.корень / "база.txt").write_text("Исходная база приёмки.\n")
        сам.гит("add", ".")
        сам.гит("commit", "-qm", "Исходная база")
        сам.база = сам.гит("rev-parse", "HEAD").decode().strip()
        сам.гит("merge", "--no-ff", "--no-commit", сам.присоединяемый)
        сам.assertEqual(сам.гит("rev-parse", "HEAD").decode().strip(), сам.база)
        сам.assertEqual((сам.корень / ".git/MERGE_HEAD").read_text().strip(), сам.присоединяемый)
        путь = сам.корень / "Инструменты/fum-kompleksnaya-proverka-repozitoriya/scripts/run-smoke-check.py"
        путь.parent.mkdir(parents=True)
        путь.write_text('''import json, os
from pathlib import Path
план = [{"ключ_проверки": "Инструменты/пример/tests", "название": "Проверка фикстуры слияния"}]
значение = {"схема": "fum.smoke-test-observations.v1", "идентификатор_запуска": os.environ["FUM_CHECK_RUN_ID"], "текущая_проверка": None, "план": план, "наблюдения": [{**план[0], "статус": "успешно", "длительность_наносекунды": 1}]}
Path(os.environ["FUM_CHECK_RUN_OBSERVATIONS_PATH"]).write_text(json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + "\\n")
''')
        (сам.корень / "результат.bin").write_bytes(bytes(range(256)))
        сам.гит("add", ".")
        сам.идентификатор = "00000000-0000-4000-8000-000000000211"
        итог = сам.фикстура.запустить(сам.идентификатор, sys.executable, str(путь))
        сам.assertEqual(итог.returncode, 0, итог.stderr)
        сам.отпечаток = сам.фикстура.запись(сам.идентификатор)["профиль_проверки"]["отпечаток_снимка"]
        итог = сам.фикстура.выполнить("закрыть")
        сам.assertEqual(итог.returncode, 0, итог.stderr)
        сам.гит("add", ".")
        # Ожидаемое дерево сохранено до коммита, а не выведено новым адаптером.
        сам.дерево = сам.гит("write-tree").decode().strip()
        сам.гит("commit", "-qm", "Сохранить принятое слияние фикстуры")
        сам.коммит = сам.гит("rev-parse", "HEAD").decode().strip()
        сам.файлы = {путь.name: путь.read_bytes() for путь in сам.фикстура.каталог_записей.iterdir()}
        сам.отчёт = сам.фикстура.отчёт.read_bytes()
        сам.имя = next(имя for имя in сам.файлы if имя != "снимок.json")

    def связать(сам, **замены):
        параметры = dict(корень_репозитория=сам.корень, сессия=str(Path(путь_запроса).parent), коммит=сам.коммит,
                         база=сам.база, присоединяемый=сам.присоединяемый, дерево=сам.дерево,
                         отпечаток_закрытия=сам.отпечаток, отпечаток_запуска=сам.отпечаток)
        return сам.адаптер.связать_отпечаток_со_слиянием(**(параметры | замены))

    def проверить(сам, **замены):
        параметры = dict(корень_репозитория=сам.корень, запрос=путь_запроса, коммит=сам.коммит,
                         база=сам.база, присоединяемый=сам.присоединяемый, дерево=сам.дерево)
        return сам.читатель.проверить_отчёт_в_слиянии(**(параметры | замены))

    def коммит_дерева(сам, дерево=None, родители=None):
        аргументы = ["commit-tree", дерево or сам.гит("write-tree").decode().strip()]
        for родитель in ([сам.база, сам.присоединяемый] if родители is None else родители):
            аргументы.extend(["-p", родитель])
        return сам.гит(*аргументы, "-m", "Проверяемый вариант").decode().strip()

    def test_реальное_слияние_и_отпечаток_действующей_обёртки(сам):
        связь = сам.связать()
        сам.assertEqual(связь["кандидат"], сам.отпечаток)
        сам.assertEqual(связь["родители"], [сам.база, сам.присоединяемый])
        сам.assertEqual(связь["дерево"], сам.дерево)
        итог = сам.проверить()
        сам.assertEqual(итог["состояние"], "подтверждён")
        сам.assertEqual(итог["финальный_запуск"], сам.идентификатор)
        сам.assertFalse(итог["завершение_обязательства_доказано"])
        with сам.assertRaises(сам.адаптер.ОшибкаОтчёта):
            сам.читатель.проверить_отчёт_в_коммите(сам.корень, сам.коммит, путь_запроса)

    def test_другая_вершина_master_с_тем_же_деревом_не_подменяет_родителя(сам):
        дерево = сам.гит("rev-parse", сам.присоединяемый + "^{tree}").decode().strip()
        другой = сам.гит("commit-tree", дерево, "-p", сам.исходная, "-m", "Другая версия master").decode().strip()
        сам.assertNotEqual(другой, сам.присоединяемый)
        with сам.assertRaises(сам.адаптер.ОшибкаОтчёта):
            сам.связать(присоединяемый=другой)

    def test_неполная_или_переписанная_граница_истории_отклоняется(сам):
        for имя, содержимое in (("shallow", сам.база + "\n"), ("info/grafts", сам.коммит + " " + сам.база + "\n")):
            путь = сам.корень / ".git" / имя
            путь.parent.mkdir(parents=True, exist_ok=True)
            путь.write_text(содержимое)
            try:
                with сам.subTest(имя=имя), сам.assertRaises(сам.адаптер.ОшибкаОтчёта):
                    сам.связать()
            finally:
                путь.unlink()


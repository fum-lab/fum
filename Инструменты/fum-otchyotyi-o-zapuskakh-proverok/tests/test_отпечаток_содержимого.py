from __future__ import annotations

import importlib.util
from pathlib import Path
import subprocess
import tempfile
import unittest


путь_модуля = Path(__file__).resolve().parents[1] / "scripts" / "отчёты_о_запусках_проверок.py"
спецификация = importlib.util.spec_from_file_location("отчёты_для_отпечатка", путь_модуля)
модуль = importlib.util.module_from_spec(спецификация)
assert спецификация.loader is not None
спецификация.loader.exec_module(модуль)


class ТестыОтпечаткаСодержимого(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name)
        сам.сессия = Path("Журнал/2026-09-08_10-00-00_MSK_проверка")
        (сам.корень / сам.сессия).mkdir(parents=True)
        (сам.корень / сам.сессия / "запрос.md").write_text("Запрос\n")
        сам.файл = сам.корень / "содержание.md"
        сам.файл.write_text("Исходное содержание\n")
        сам.выполнить_гит("init", "-q")
        сам.выполнить_гит("config", "user.name", "FUM Тесты")
        сам.выполнить_гит("config", "user.email", "fum-tests@example.invalid")
        сам.выполнить_гит("add", ".")
        сам.выполнить_гит("commit", "-qm", "Исходный снимок")

    def выполнить_гит(сам, *аргументы, корень=None):
        return subprocess.check_output(["git", *аргументы], cwd=корень or сам.корень)

    def отпечаток(сам):
        return модуль.вычислить_отпечаток_содержимого(сам.корень, сам.сессия)

    def test_индекс_и_коммиты_не_меняют_содержательный_отпечаток(сам):
        исходный = сам.отпечаток()
        сам.файл.write_text("Новое содержание\n")
        изменённый = сам.отпечаток()
        сам.assertNotEqual(исходный, изменённый)
        сам.выполнить_гит("add", ".")
        сам.assertEqual(сам.отпечаток(), изменённый)
        сам.выполнить_гит("commit", "-qm", "Контрольная точка")
        сам.assertEqual(сам.отпечаток(), изменённый)
        сам.выполнить_гит("commit", "--allow-empty", "-qm", "Пустая точка")
        сам.assertEqual(сам.отпечаток(), изменённый)
        сам.файл.write_text("Исходное содержание\n")
        сам.assertEqual(сам.отпечаток(), исходный)

    def test_новый_файл_переименование_удаление_и_режим_различаются(сам):
        исходный = сам.отпечаток()
        новый = сам.корень / "новый.txt"
        новый.write_text("Новый\n")
        добавлен = сам.отпечаток()
        сам.assertNotEqual(добавлен, исходный)
        сам.выполнить_гит("add", ".")
        сам.assertEqual(сам.отпечаток(), добавлен)
        новый.rename(сам.корень / "другой.txt")
        сам.assertNotEqual(сам.отпечаток(), добавлен)
        (сам.корень / "другой.txt").unlink()
        сам.assertEqual(сам.отпечаток(), исходный)
        сам.файл.chmod(0o755)
        сам.assertNotEqual(сам.отпечаток(), исходный)
        сам.файл.chmod(0o644)
        сам.файл.unlink()
        сам.assertNotEqual(сам.отпечаток(), исходный)

    def test_исключены_только_собственные_отчёт_запуски_и_точная_проекция(сам):
        исходный = сам.отпечаток()
        for путь in (
            сам.сессия / "отчёт.md",
            сам.сессия / "материалы/запуски-проверок/1.json",
            Path("Proyekcii/вывод.txt"),
        ):
            полный = сам.корень / путь
            полный.parent.mkdir(parents=True, exist_ok=True)
            полный.write_text("Производное\n")
        сам.assertEqual(сам.отпечаток(), исходный)
        сам.выполнить_гит("add", ".")
        сам.assertEqual(сам.отпечаток(), исходный)
        сам.выполнить_гит("commit", "-qm", "Только исключённые материалы")
        сам.assertEqual(сам.отпечаток(), исходный)
        чужой = сам.корень / "Журнал/чужая-задача/отчёт.md"
        чужой.parent.mkdir(parents=True)
        чужой.write_text("Чужой канонический отчёт\n")
        сам.assertNotEqual(сам.отпечаток(), исходный)

    def test_похожие_имена_проекции_не_исключаются(сам):
        исходный = сам.отпечаток()
        for имя in ("proyekcii", "Proyekcii-копия", "вложенная/Proyekcii"):
            with сам.subTest(имя=имя):
                путь = сам.корень / имя / "файл.txt"
                путь.parent.mkdir(parents=True, exist_ok=True)
                путь.write_text("Каноническое\n")
                сам.assertNotEqual(сам.отпечаток(), исходный)
                путь.unlink()

    def test_символическая_ссылка_не_читается_как_внешнее_содержимое(сам):
        ссылка = сам.корень / "ссылка"
        ссылка.symlink_to("несуществующая-внешняя-цель")
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()
        сам.выполнить_гит("add", ".")
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()

    def test_конфликт_индекса_не_получает_приёмочный_отпечаток(сам):
        сам.выполнить_гит("checkout", "-qb", "изменение")
        сам.файл.write_text("Сторона один\n")
        сам.выполнить_гит("commit", "-qam", "Одна сторона")
        сам.выполнить_гит("checkout", "-q", "HEAD~1")
        сам.файл.write_text("Сторона два\n")
        сам.выполнить_гит("commit", "-qam", "Другая сторона")
        subprocess.run(["git", "merge", "изменение"], cwd=сам.корень, capture_output=True)
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()

    def test_изменение_только_индексного_объекта_и_режима_не_меняет_содержимое(сам):
        прежний_объект = сам.выполнить_гит("rev-parse", "HEAD:содержание.md").decode().strip()
        сам.файл.write_text("Новые дисковые байты\n")
        сам.выполнить_гит("add", ".")
        содержательный = сам.отпечаток()
        снимок = модуль.вычислить_отпечаток_снимка(сам.корень, сам.сессия)
        сам.выполнить_гит("update-index", "--cacheinfo", "100644", прежний_объект, "содержание.md")
        сам.assertEqual(сам.отпечаток(), содержательный)
        сам.assertNotEqual(модуль.вычислить_отпечаток_снимка(сам.корень, сам.сессия), снимок)
        сам.выполнить_гит("update-index", "--chmod=+x", "содержание.md")
        сам.assertEqual(сам.отпечаток(), содержательный)

    def test_удаление_остаётся_тем_же_после_индекса_и_коммита(сам):
        сам.файл.unlink()
        удалённый = сам.отпечаток()
        сам.выполнить_гит("add", "-u")
        сам.assertEqual(сам.отпечаток(), удалённый)
        сам.выполнить_гит("commit", "-qm", "Удаление")
        сам.assertEqual(сам.отпечаток(), удалённый)

    def test_родительская_символическая_ссылка_отклоняется(сам):
        каталог = сам.корень / "каталог"
        каталог.mkdir()
        (каталог / "файл.txt").write_text("Содержимое\n")
        сам.выполнить_гит("add", ".")
        каталог.rename(сам.корень / "исходный")
        каталог.symlink_to("исходный", target_is_directory=True)
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()

    def test_вершина_подмодуля_отличается_от_индекса_и_коммита_родителя(сам):
        временный_пакет = tempfile.TemporaryDirectory()
        сам.addCleanup(временный_пакет.cleanup)
        исходник = Path(временный_пакет.name)
        сам.выполнить_гит("init", "-q", корень=исходник)
        сам.выполнить_гит("config", "user.name", "FUM Тесты", корень=исходник)
        сам.выполнить_гит("config", "user.email", "fum-tests@example.invalid", корень=исходник)
        (исходник / "код.txt").write_text("Версия А\n")
        сам.выполнить_гит("add", ".", корень=исходник)
        сам.выполнить_гит("commit", "-qm", "Версия А", корень=исходник)
        первая = сам.выполнить_гит("rev-parse", "HEAD", корень=исходник).decode().strip()
        (исходник / "код.txt").write_text("Версия Б\n")
        сам.выполнить_гит("commit", "-qam", "Версия Б", корень=исходник)
        сам.выполнить_гит("-c", "protocol.file.allow=always", "submodule", "add", "-q", str(исходник), "пакет")
        сам.выполнить_гит("commit", "-qm", "Закрепить пакет")
        вторая = сам.отпечаток()
        пакет = сам.корень / "пакет"
        сам.выполнить_гит("checkout", "-q", первая, корень=пакет)
        первая_содержательная = сам.отпечаток()
        сам.assertNotEqual(первая_содержательная, вторая)
        сам.выполнить_гит("add", "пакет")
        сам.assertEqual(сам.отпечаток(), первая_содержательная)
        сам.выполнить_гит("commit", "-qm", "Сменить пакет")
        сам.assertEqual(сам.отпечаток(), первая_содержательная)
        сам.выполнить_гит("config", "submodule.пакет.ignore", "all")
        (пакет / "код.txt").write_text("Незакреплённое изменение\n")
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()
        сам.выполнить_гит("checkout", "--", "код.txt", корень=пакет)
        for скрытие in ("assume-unchanged", "skip-worktree", "режим"):
            with сам.subTest(скрытие=скрытие):
                if скрытие == "режим":
                    сам.выполнить_гит("config", "core.filemode", "false", корень=пакет)
                    (пакет / "код.txt").chmod(0o755)
                else:
                    сам.выполнить_гит("update-index", "--" + скрытие, "код.txt", корень=пакет)
                    (пакет / "код.txt").write_text("Скрытое изменение\n")
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    сам.отпечаток()
            сам.выполнить_гит("update-index", "--no-assume-unchanged", "--no-skip-worktree", "код.txt", корень=пакет)
            (пакет / "код.txt").write_text("Версия А\n")
            (пакет / "код.txt").chmod(0o644)
        (пакет / "код.txt").chmod(0o755)
        сам.выполнить_гит("update-index", "--chmod=+x", "код.txt", корень=пакет)
        сам.выполнить_гит("-c", "user.name=FUM Тесты", "-c", "user.email=fum-tests@example.invalid", "commit", "-qm", "Исполняемый пакет", корень=пакет)
        (пакет / "код.txt").chmod(0o645)
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()
        (пакет / "код.txt").chmod(0o755)
        сам.выполнить_гит("-c", "protocol.file.allow=always", "submodule", "add", "-q", str(исходник), "вложенный", корень=пакет)
        сам.выполнить_гит("-c", "user.name=FUM Тесты", "-c", "user.email=fum-tests@example.invalid", "commit", "-qm", "Вложенный пакет", корень=пакет)
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()
        сам.выполнить_гит("submodule", "deinit", "-f", "--", "пакет")
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()


if __name__ == "__main__":
    unittest.main()

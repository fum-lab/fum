    def test_вершина_подмодуля_отличается_от_индекса_и_коммита_родителя(сам):
        временный_пакет = tempfile.TemporaryDirectory()
        сам.addCleanup(временный_пакет.cleanup)
        исходник = Path(временный_пакет.name)
        сам.выполнить_гит("init", "-q", корень=исходник)
        сам.выполнить_гит("config", "user.name", "FUM Тесты", корень=исходник)
        сам.выполнить_гит("config", "user.email", "fum-tests@example.invalid", корень=исходник)
        (исходник / "код.txt").write_text("Версия А\n")
        сам.выполнить_гит("add", ".", корень=исходник)
        сам.выполнить_гит("commit", "-qm", "Версия А", корень=исходник)
        первая = сам.выполнить_гит("rev-parse", "HEAD", корень=исходник).decode().strip()
        (исходник / "код.txt").write_text("Версия Б\n")
        сам.выполнить_гит("commit", "-qam", "Версия Б", корень=исходник)
        сам.выполнить_гит("-c", "protocol.file.allow=always", "submodule", "add", "-q", str(исходник), "пакет")
        сам.выполнить_гит("commit", "-qm", "Закрепить пакет")
        вторая = сам.отпечаток()
        пакет = сам.корень / "пакет"
        сам.выполнить_гит("checkout", "-q", первая, корень=пакет)
        первая_содержательная = сам.отпечаток()
        сам.assertNotEqual(первая_содержательная, вторая)
        сам.выполнить_гит("add", "пакет")
        сам.assertEqual(сам.отпечаток(), первая_содержательная)
        сам.выполнить_гит("commit", "-qm", "Сменить пакет")
        сам.assertEqual(сам.отпечаток(), первая_содержательная)
        сам.выполнить_гит("config", "submodule.пакет.ignore", "all")
        (пакет / "код.txt").write_text("Незакреплённое изменение\n")
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()
        сам.выполнить_гит("checkout", "--", "код.txt", корень=пакет)
        for скрытие in ("assume-unchanged", "skip-worktree", "режим"):
            with сам.subTest(скрытие=скрытие):
                if скрытие == "режим":
                    сам.выполнить_гит("config", "core.filemode", "false", корень=пакет)
                    (пакет / "код.txt").chmod(0o755)
                else:
                    сам.выполнить_гит("update-index", "--" + скрытие, "код.txt", корень=пакет)
                    (пакет / "код.txt").write_text("Скрытое изменение\n")
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    сам.отпечаток()
            сам.выполнить_гит("update-index", "--no-assume-unchanged", "--no-skip-worktree", "код.txt", корень=пакет)
            (пакет / "код.txt").write_text("Версия А\n")
            (пакет / "код.txt").chmod(0o644)
        (пакет / "код.txt").chmod(0o755)
        сам.выполнить_гит("update-index", "--chmod=+x", "код.txt", корень=пакет)
        сам.выполнить_гит("-c", "user.name=FUM Тесты", "-c", "user.email=fum-tests@example.invalid", "commit", "-qm", "Исполняемый пакет", корень=пакет)
        (пакет / "код.txt").chmod(0o645)
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()
        (пакет / "код.txt").chmod(0o755)
        сам.выполнить_гит("-c", "protocol.file.allow=always", "submodule", "add", "-q", str(исходник), "вложенный", корень=пакет)
        сам.выполнить_гит("-c", "user.name=FUM Тесты", "-c", "user.email=fum-tests@example.invalid", "commit", "-qm", "Вложенный пакет", корень=пакет)
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()
        сам.выполнить_гит("submodule", "deinit", "-f", "--", "пакет")
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.отпечаток()



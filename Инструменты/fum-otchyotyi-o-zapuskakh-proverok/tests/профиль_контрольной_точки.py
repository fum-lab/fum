#!/usr/bin/env python3
"""Сравнить стоимость контрольной точки до и после разрешения своей записи."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import statistics
import subprocess
import sys
import tempfile
import time
import types
import uuid
from pathlib import Path


ПУТЬ_РЕАЛИЗАЦИИ = Path(
    "Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts/"
    "отчёты_о_запусках_проверок.py"
)


def выполнить_git(корень: Path, *аргументы: str) -> bytes:
    return subprocess.run(
        ["git", *аргументы],
        cwd=корень,
        check=True,
        capture_output=True,
    ).stdout


def загрузить_из_байтов(имя: str, путь: Path, байты: bytes) -> types.ModuleType:
    модуль = types.ModuleType(имя)
    модуль.__file__ = str(путь)
    exec(compile(байты, str(путь), "exec"), модуль.__dict__)
    модуль.КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(байты).hexdigest()
    return модуль


def разобрать_аргументы() -> argparse.Namespace:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--корень", type=Path, default=Path.cwd())
    разбор.add_argument("--база", required=True, help="полный OID исходного коммита")
    разбор.add_argument("--выход", type=Path, required=True)
    разбор.add_argument("--записей", type=int, default=300)
    разбор.add_argument("--раундов", type=int, default=7)
    return разбор.parse_args()


def создать_фикстуру(корень: Path, модуль: types.ModuleType, число: int) -> tuple[Path, str]:
    сессия = "Журнал/2026-09-30_00-00-00_MSK_профиль-контрольной-точки"
    каталог = корень / сессия
    записи = каталог / "материалы" / "запуски-проверок"
    записи.mkdir(parents=True)
    запрос = каталог / "запрос.md"
    запрос.write_text(
        "# Исходный запрос 2026-09-30 00:00:00 MSK\n\n"
        "## Текст запроса\n\n````text\nПрофиль.\n````\n",
        encoding="utf-8",
    )
    относительный_запрос = f"{сессия}/запрос.md"
    for порядок in range(1, число + 1):
        идентификатор = str(uuid.uuid5(uuid.NAMESPACE_URL, f"fum-profile-{порядок}"))
        запись = {
            "схема": модуль.СХЕМА_ЗАПУСКА,
            "идентификатор": идентификатор,
            "сессия": относительный_запрос,
            "порядок": порядок,
            "исполнитель": "профиль",
            "вызов": "контрольная точка",
            "состояние": "завершён",
            "длительность_наносекунды": 1_000_000,
            "статус": "успешно",
            "код_завершения": 0,
            "пояснение": None,
        }
        (записи / f"{порядок}_{идентификатор}.json").write_bytes(
            модуль.канонические_машинные_байты(запись)
        )
    журнал = модуль.прочитать_историю_проверок(записи, относительный_запрос)
    блок = модуль.сформировать_блок_истории(
        журнал,
        модуль.ОТКРЫТЫЙ_МАРКЕР,
        *модуль.текущий_контекст_проверок(корень, относительный_запрос, журнал),
    )
    отчёт = каталог / "отчёт.md"
    отчёт.write_text(
        "# Отчёт профиля\n\n## Профиль времени выполнения\n\n"
        "### Прямые запуски проверок\n\n"
        f"{блок}\n\n## Проверки\n\nНеизменяемый хвост.\n",
        encoding="utf-8",
    )
    return запрос, относительный_запрос


def проверить_и_измерить(
    модуль: types.ModuleType,
    корень: Path,
    запрос: Path,
    раундов: int,
) -> list[int]:
    ошибки = модуль.проверить_журнал_сессии(корень, запрос, контрольная_точка=True)
    if ошибки:
        raise RuntimeError("контрольная точка отказала: " + "; ".join(ошибки))
    времена = []
    for _ in range(раундов):
        начало = time.perf_counter_ns()
        ошибки = модуль.проверить_журнал_сессии(
            корень,
            запрос,
            контрольная_точка=True,
        )
        времена.append(time.perf_counter_ns() - начало)
        if ошибки:
            raise RuntimeError("контрольная точка отказала: " + "; ".join(ошибки))
    return времена


def main() -> int:
    аргументы = разобрать_аргументы()
    корень = аргументы.корень.resolve(strict=True)
    if аргументы.записей < 1 or аргументы.раундов < 3:
        raise ValueError("нужны положительное число записей и не менее трёх раундов")
    база = выполнить_git(корень, "rev-parse", "--verify", аргументы.база + "^{commit}").decode().strip()
    if база != аргументы.база:
        raise ValueError("база должна быть полным точным OID коммита")
    путь_исходника = корень / ПУТЬ_РЕАЛИЗАЦИИ
    байты_до = выполнить_git(корень, "show", f"{база}:{ПУТЬ_РЕАЛИЗАЦИИ.as_posix()}")
    байты_после = путь_исходника.read_bytes()
    до = загрузить_из_байтов("fum_профиль_до", путь_исходника, байты_до)
    после = загрузить_из_байтов("fum_профиль_после", путь_исходника, байты_после)

    with tempfile.TemporaryDirectory(prefix="fum-checkpoint-profile-") as временный:
        корень_фикстуры = Path(временный)
        запрос, относительный = создать_фикстуру(корень_фикстуры, после, аргументы.записей)
        каталог_записей = (
            корень_фикстуры
            / Path(относительный).parent
            / "материалы"
            / "запуски-проверок"
        )
        журнал_до = до.прочитать_историю_проверок(
            каталог_записей,
            относительный,
        )
        журнал_после = после.прочитать_историю_проверок(
            каталог_записей,
            относительный,
        )
        if [x[1] for x in журнал_до] != [x[1] for x in журнал_после]:
            raise RuntimeError("исходная и изменённая реализации читают разные записи")
        блок_до = до.сформировать_блок_истории(
            журнал_до,
            до.ОТКРЫТЫЙ_МАРКЕР,
            *до.текущий_контекст_проверок(корень_фикстуры, относительный, журнал_до),
        )
        блок_после = после.сформировать_блок_истории(
            журнал_после,
            после.ОТКРЫТЫЙ_МАРКЕР,
            *после.текущий_контекст_проверок(корень_фикстуры, относительный, журнал_после),
        )
        if блок_до != блок_после:
            raise RuntimeError("рендер предпросмотра изменился на терминальной истории")
        времена_до: list[int] = []
        времена_после: list[int] = []
        for номер in range(аргументы.раундов):
            пары = (
                ((до, времена_до), (после, времена_после))
                if номер % 2 == 0
                else ((после, времена_после), (до, времена_до))
            )
            for модуль, значения in пары:
                значения.extend(
                    проверить_и_измерить(
                        модуль,
                        корень_фикстуры,
                        Path(относительный),
                        1,
                    )
                )

    медиана_до = statistics.median(времена_до)
    медиана_после = statistics.median(времена_после)
    результат = {
        "схема": "fum.профиль-контрольной-точки.1",
        "база_oid": база,
        "хэш_исходника_до": hashlib.sha256(байты_до).hexdigest(),
        "хэш_исходника_после": hashlib.sha256(байты_после).hexdigest(),
        "записей": аргументы.записей,
        "чередующихся_раундов": аргументы.раундов,
        "порядок": "до/после с чередованием",
        "медиана_до_нс": медиана_до,
        "медиана_после_нс": медиана_после,
        "изменение_процентов": (медиана_после / медиана_до - 1) * 100,
        "измерения_до_нс": времена_до,
        "измерения_после_нс": времена_после,
        "предпросмотр_одинаков": True,
        "среда_python": sys.version.split()[0],
        "среда_os": platform.platform(),
    }
    выход = аргументы.выход if аргументы.выход.is_absolute() else корень / аргументы.выход
    выход = выход.resolve()
    if not выход.is_relative_to(корень) or not выход.parent.is_dir() or выход.exists():
        raise ValueError("новый путь профиля должен быть свободным файлом внутри checkout")
    данные = (json.dumps(результат, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()
    with выход.open("xb") as файл:
        файл.write(данные)
        файл.flush()
        os.fsync(файл.fileno())
    if выход.read_bytes() != данные:
        raise RuntimeError("профиль не совпадает с подтверждённым чтением")
    print(json.dumps(результат, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

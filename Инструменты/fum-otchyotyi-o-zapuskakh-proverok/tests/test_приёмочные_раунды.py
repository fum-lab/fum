def запись(порядок=1, класс="адресная", *, версия=4, отпечаток=содержимое, гит=снимок):
    идентификатор = f"00000000-0000-4000-8000-{порядок:012d}"
    план = [{"ключ_проверки": ключ, "название": "Полный набор"}] if класс == "полная" else None
    значение = {
        "схема": f"fum.test-run.v{версия}",
        "идентификатор": идентификатор,
        "сессия": сессия,
        "порядок": порядок,
        "исполнитель": "Корень",
        "вызов": "Проверка контракта",
        "состояние": "завершён",
        "длительность_наносекунды": 1000,
        "статус": "успешно",
        "код_завершения": 0,
        "пояснение": None,
        "план": план,
        "наблюдения": [{**элемент, "статус": "успешно", "длительность_наносекунды": 1} for элемент in (план or [])],
        "профиль_проверки": {
            "класс": класс,
            "отпечаток_снимка": гит,
            "полные_наборы": [ключ] if класс != "адресная" else [],
            "основание": "не_покрывается_финальной_комплексной_проверкой" if класс == "диагностическая" else None,
            "идентификатор_отказа": None,
            "ожидаемое_свидетельство": "Проверить отдельную границу" if класс == "диагностическая" else None,
        },
    }
    if версия == 4:
        значение.update({"отпечаток_содержимого": отпечаток, "переход_схемы": None})
    return упаковать(значение)


def упаковать(значение):
    путь = Path(f"{значение['порядок']}_{значение['идентификатор']}.json")
    return путь, значение, модуль.канонические_машинные_байты(значение)


class ТестыЧитателяРаундов(unittest.TestCase):
    def проверить(сам, элемент):
        путь, значение, _ = элемент
        return модуль.проверить_запись(значение, путь.name, сессия)

    def test_четвёртая_версия_принимает_три_класса(сам):
        for класс in ("адресная", "диагностическая", "полная"):
            with сам.subTest(класс=класс):
                элемент = запись(класс=класс)
                сам.assertEqual(сам.проверить(элемент), элемент[1])

    def test_четвёртая_версия_сохраняет_строгие_активные_и_терминальные_поля(сам):
        значение = запись(класс="полная")[1]
        значение.update({"состояние": "выполняется", "план": None, "наблюдения": []})
        значение["профиль_проверки"]["полные_наборы"] = []
        for поле in ("длительность_наносекунды", "статус", "код_завершения", "пояснение"):
            значение[поле] = None
        сам.проверить(упаковать(значение))
        значение["код_завершения"] = 0
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.проверить(упаковать(значение))
        значение = запись(класс="полная")[1]
        значение["наблюдения"] = []
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            сам.проверить(упаковать(значение))

    def test_новые_поля_строго_проверяются_и_не_разрешены_в_старой_схеме(сам):
        правильная = запись()[1]
        случаи = []
        for поле in ("отпечаток_содержимого", "переход_схемы"):
            изменённая = copy.deepcopy(правильная)
            del изменённая[поле]
            случаи.append(изменённая)
        for неверное in (None, "", "sha256:" + "Z" * 64, 1, {}):
            изменённая = copy.deepcopy(правильная)
            изменённая["отпечаток_содержимого"] = неверное
            случаи.append(изменённая)
        for неверное in ({}, [], True, "переход"):
            изменённая = copy.deepcopy(правильная)
            изменённая["переход_схемы"] = неверное
            случаи.append(изменённая)
        изменённая = copy.deepcopy(правильная)
        изменённая["схема"] = "fum.test-run.v3"
        случаи.append(изменённая)
        for значение in случаи:
            with сам.subTest(значение=значение):
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    сам.проверить(упаковать(значение))

    def test_старый_план_не_разрешает_два_успешных_полных_снимка(сам):
        записи = [запись(1, "полная", версия=3), запись(2, "полная", версия=3, гит="sha256:" + "c" * 64)]
        план = модуль.построить_план_успешной_сессии(записи, "sha256:" + "c" * 64)
        сам.assertEqual(план["состояние"], "не готов")
        сам.assertFalse(план["доказанные_условия"]["ровно_один_успешный_полный_прогон"])


def переход(префикс):
    return {
        "последний_порядок": max(элемент[1]["порядок"] for элемент in префикс),
        "число_записей": len(префикс),
        "хэш_префикса": модуль.вычислить_хэш_префикса_раундов(префикс),
        "исходный_коммит": "c" * 40,
        "изменения_контракта": [{
            "путь": "Инструменты/fum-otchyotyi-o-zapuskakh-proverok/scripts/отчёты_о_запусках_проверок.py",
            "до_sha256": "sha256:" + "d" * 64,
            "после_sha256": "sha256:" + "e" * 64,
        }],
    }


class ТестыГраницыРаундов(unittest.TestCase):
    def история(сам):
        префикс = [запись(1, версия=3), запись(2, "полная", версия=3)]
        новая = запись(3)[1]
        новая["переход_схемы"] = переход(префикс)
        return [*префикс, упаковать(новая), запись(4, "полная")]

    def test_новая_история_и_переход_после_старого_префикса_сохраняют_байты(сам):
        новые = [запись(), запись(2, "полная")]
        сам.assertEqual(модуль.проверить_историю_раундов(новые), новые)
        история = сам.история()
        исходные = copy.deepcopy(история)
        сам.assertEqual(модуль.проверить_историю_раундов(list(reversed(история))), история[2:])
        сам.assertEqual(история, исходные)

    def test_смена_имени_байтов_или_длины_префикса_отклоняется(сам):
        история = сам.история()
        случаи = [история[1:]]
        имя, значение, байты = история[0]
        случаи.append([(имя, значение, байты + b" "), *история[1:]])
        случаи.append([(имя.with_name("0" + имя.name), значение, байты), *история[1:]])
        for случай in случаи:
            with сам.subTest(случай=случай):
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    модуль.проверить_историю_раундов(случай)

    def test_граница_однократна_обязательна_и_схема_не_возвращается_назад(сам):
        история = сам.история()
        случаи = []
        без_границы = copy.deepcopy(история)
        без_границы[2][1]["переход_схемы"] = None
        случаи.append([упаковать(элемент[1]) for элемент in без_границы])
        повтор = copy.deepcopy(история)
        повтор[3][1]["переход_схемы"] = повтор[2][1]["переход_схемы"]
        случаи.append([упаковать(элемент[1]) for элемент in повтор])
        случаи.append([*история, запись(5, версия=3)])
        случаи.append([запись(2)])
        случаи.append([запись(), запись(3)])
        for случай in случаи:
            with сам.subTest(случай=случай):
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    модуль.проверить_историю_раундов(случай)

    def test_активный_префикс_рассогласованные_байты_и_дубли_отклоняются(сам):
        история = сам.история()
        рассогласованные = copy.deepcopy(история)
        рассогласованные[0][1]["вызов"] = "Изменённая копия"
        активный = copy.deepcopy(история)
        активный[0][1].update({"состояние": "выполняется", "статус": None, "код_завершения": None, "длительность_наносекунды": None})
        активный = [упаковать(элемент[1]) for элемент in активный]
        активный[2][1]["переход_схемы"] = переход(активный[:2])
        активный[2] = упаковать(активный[2][1])
        for случай in (рассогласованные, [история[0], *история], активный):
            with сам.subTest(случай=случай):
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    модуль.проверить_историю_раундов(случай)

    def test_поля_границы_проверяются_даже_без_живого_репозитория(сам):
        история = сам.история()
        сам.assertEqual(модуль.проверить_историю_раундов(история), история[2:])
        случаи = []
        for поле, значение in (("последний_порядок", True), ("число_записей", 0), ("исходный_коммит", "HEAD"), ("изменения_контракта", [])):
            неверная = copy.deepcopy(история[2][1])
            неверная["переход_схемы"][поле] = значение
            случаи.append(неверная)
        неверная = copy.deepcopy(история[2][1])
        изменение = неверная["переход_схемы"]["изменения_контракта"][0]
        изменение["после_sha256"] = изменение["до_sha256"]
        случаи.append(неверная)
        for значение in случаи:
            with сам.subTest(значение=значение):
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    модуль.проверить_историю_раундов([*история[:2], упаковать(значение), история[3]])


class ТестыГраницыСовместимости(unittest.TestCase):
    def test_старые_форматы_не_принимают_новые_записи_как_исторические(сам):
        записи = [запись(класс="полная")]
        for действие in (
            lambda: модуль.построить_план_успешной_сессии(записи, снимок),
            lambda: модуль.ожидаемый_снимок(записи, сессия),
            lambda: модуль.сформировать_блок(записи, модуль.ОТКРЫТЫЙ_МАРКЕР),
        ):
            with сам.subTest(действие=действие):
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    действие()

    def test_типы_сырых_байтов_проверяются_отдельно_от_равенства_значений(сам):
        путь, значение, _ = запись()
        for поле, неверное in (("порядок", 1.0), ("код_завершения", False)):
            данные = copy.deepcopy(значение)
            данные[поле] = неверное
            байты = json.dumps(данные, ensure_ascii=False).encode("utf-8")
            with сам.subTest(поле=поле):
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    модуль.проверить_историю_раундов([(путь, значение, байты)])

    def test_старые_команды_не_получают_новую_схему_через_дисковый_загрузчик(сам):
        with tempfile.TemporaryDirectory() as папка:
            каталог = Path(папка)
            путь, значение, байты = запись()
            (каталог / путь.name).write_bytes(байты)
            with сам.assertRaises(модуль.ОшибкаОтчёта):
                модуль.прочитать_записи(каталог, сессия)
            прочитанные = модуль.прочитать_записи(каталог, сессия, разрешить_раунды=True)
            сам.assertEqual(прочитанные[0][1], значение)

    def test_самостоятельная_история_требует_каноническую_сессию(сам):
        for неверная in (None, "", "../Журнал/задача/запрос.md", "Вне/задача/запрос.md", "Журнал/задача/отчёт.md", "Журнал/лишнее/задача/запрос.md"):
            значение = запись()[1]
            значение["сессия"] = неверная
            with сам.subTest(сессия=неверная):
                with сам.assertRaises(модуль.ОшибкаОтчёта):
                    модуль.проверить_историю_раундов([упаковать(значение)])

    def test_вторая_схема_не_получает_неявную_миграцию(сам):
        старая = запись(1, "полная", версия=3)[1]
        старая["схема"] = "fum.test-run.v2"
        del старая["профиль_проверки"]
        префикс = [упаковать(старая)]
        новая = запись(2)[1]
        новая["переход_схемы"] = переход(префикс)
        with сам.assertRaises(модуль.ОшибкаОтчёта):
            модуль.проверить_историю_раундов([*префикс, упаковать(новая)])


class ТестыПланаРаундов(unittest.TestCase):
    другое_содержимое = "sha256:" + "c" * 64
    другой_снимок = "sha256:" + "d" * 64

    def план(сам, записи, *, гит=снимок, вход=содержимое):
        return модуль.построить_план_раундов(записи, гит, вход)

    def отказ(сам, элемент):
        значение = copy.deepcopy(элемент[1])
        значение.update({"статус": "неуспешно", "код_завершения": 1})
        for наблюдение in значение["наблюдения"]:
            наблюдение["статус"] = "неуспешно"
        return упаковать(значение)

    def test_два_разных_содержательных_раунда_допустимы(сам):
        записи = [запись(1, "полная"), запись(2, "полная", отпечаток=сам.другое_содержимое, гит=сам.другой_снимок)]
        итог = сам.план(записи, гит=сам.другой_снимок, вход=сам.другое_содержимое)
        сам.assertEqual(итог["состояние"], "готов")
        сам.assertEqual(итог["полные_попытки"], 2)

    def test_другая_вершина_возврат_содержимого_и_отказ_не_разрешают_повтор(сам):
        первый = запись(1, "полная")
        случаи = [
            [первый, запись(2, "полная", гит=сам.другой_снимок)],
            [первый, запись(2, "полная", отпечаток=сам.другое_содержимое), запись(3, "полная")],
            [сам.отказ(первый), запись(2, "полная")],
        ]
        for номер, записи in enumerate(случаи):
            with сам.subTest(вариант=номер):
                итог = сам.план(записи)
                сам.assertEqual(итог["состояние"], "не готов")
                сам.assertFalse(итог["доказанные_условия"]["нет_повторных_полных_попыток"])

    def test_финал_требует_оба_отпечатка_последнюю_полную_запись_и_отсутствие_активных(сам):
        полный = запись(1, "полная")
        сам.assertEqual(сам.план([полный])["состояние"], "готов")
        сам.assertEqual(сам.план([полный], гит=сам.другой_снимок)["состояние"], "не готов")
        сам.assertEqual(сам.план([полный], вход=сам.другое_содержимое)["состояние"], "не готов")
        сам.assertEqual(сам.план([полный, запись(2)])["состояние"], "не готов")
        активная = запись(2)[1]
        активная["состояние"] = "выполняется"
        for поле in ("статус", "код_завершения", "длительность_наносекунды", "пояснение"):
            активная[поле] = None
        сам.assertFalse(сам.план([полный, упаковать(активная)])["доказанные_условия"]["нет_активных"])

    def test_локализация_связана_с_предыдущим_отказом_и_обоими_отпечатками(сам):
        отказ = сам.отказ(запись(1, "полная"))
        диагностика = запись(2, "диагностическая")[1]
        диагностика["профиль_проверки"].update({"основание": "локализация_наблюдаемого_отказа", "идентификатор_отказа": отказ[1]["идентификатор"]})
        финал = запись(3, "полная", отпечаток=сам.другое_содержимое)
        сам.assertEqual(сам.план([отказ, упаковать(диагностика), финал], вход=сам.другое_содержимое)["состояние"], "готов")
        for поле in ("содержимое", "гит", "идентификатор"):
            неверная = copy.deepcopy(диагностика)
            if поле == "содержимое":
                неверная["отпечаток_содержимого"] = сам.другое_содержимое
            elif поле == "гит":
                неверная["профиль_проверки"]["отпечаток_снимка"] = сам.другой_снимок
            else:
                неверная["профиль_проверки"]["идентификатор_отказа"] = финал[1]["идентификатор"]
            with сам.subTest(поле=поле):
                сам.assertEqual(сам.план([отказ, упаковать(неверная), финал], вход=сам.другое_содержимое)["состояние"], "не готов")

    def test_перекрытия_и_неуспешная_непокрытая_диагностика_не_скрываются(сам):
        диагностика = запись(1, "диагностическая")[1]
        финал = запись(2, "полная")
        сам.assertEqual(сам.план([упаковать(диагностика), финал])["состояние"], "не готов")
        диагностика["профиль_проверки"]["полные_наборы"] = ["Инструменты/fum-other/tests"]
        сам.assertEqual(сам.план([упаковать(диагностика), финал])["состояние"], "готов")
        сам.assertEqual(сам.план([сам.отказ(упаковать(диагностика)), финал])["состояние"], "не готов")
        история = [запись(1, "диагностическая"), финал, запись(3, "полная", отпечаток=сам.другое_содержимое)]
        сам.assertEqual(сам.план(история, вход=сам.другое_содержимое)["состояние"], "не готов")

    def test_старый_префикс_сохраняется_и_его_нарушения_не_стираются(сам):
        история = ТестыГраницыРаундов().история()
        сам.assertEqual(сам.план(история)["состояние"], "готов")
        история[0] = запись(1, "полная", версия=3)
        история[2][1]["переход_схемы"] = переход(история[:2])
        история[2] = упаковать(история[2][1])
        итог = сам.план(история)
        сам.assertEqual(итог["состояние"], "не готов")
        сам.assertFalse(итог["доказанные_условия"]["исторические_нарушения_отсутствуют"])



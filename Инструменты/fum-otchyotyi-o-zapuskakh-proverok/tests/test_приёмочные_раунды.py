class ТестыПланаРаундов(unittest.TestCase):
    другое_содержимое = "sha256:" + "c" * 64
    другой_снимок = "sha256:" + "d" * 64

    def план(сам, записи, *, гит=снимок, вход=содержимое):
        return модуль.построить_план_раундов(записи, гит, вход)

    def отказ(сам, элемент):
        значение = copy.deepcopy(элемент[1])
        значение.update({"статус": "неуспешно", "код_завершения": 1})
        for наблюдение in значение["наблюдения"]:
            наблюдение["статус"] = "неуспешно"
        return упаковать(значение)

    def test_два_разных_содержательных_раунда_допустимы(сам):
        записи = [запись(1, "полная"), запись(2, "полная", отпечаток=сам.другое_содержимое, гит=сам.другой_снимок)]
        итог = сам.план(записи, гит=сам.другой_снимок, вход=сам.другое_содержимое)
        сам.assertEqual(итог["состояние"], "готов")
        сам.assertEqual(итог["полные_попытки"], 2)

    def test_другая_вершина_возврат_содержимого_и_отказ_не_разрешают_повтор(сам):
        первый = запись(1, "полная")
        случаи = [
            [первый, запись(2, "полная", гит=сам.другой_снимок)],
            [первый, запись(2, "полная", отпечаток=сам.другое_содержимое), запись(3, "полная")],
            [сам.отказ(первый), запись(2, "полная")],
        ]
        for номер, записи in enumerate(случаи):
            with сам.subTest(вариант=номер):
                итог = сам.план(записи)
                сам.assertEqual(итог["состояние"], "не готов")
                сам.assertFalse(итог["доказанные_условия"]["нет_повторных_полных_попыток"])

    def test_финал_требует_оба_отпечатка_последнюю_полную_запись_и_отсутствие_активных(сам):
        полный = запись(1, "полная")
        сам.assertEqual(сам.план([полный])["состояние"], "готов")
        сам.assertEqual(сам.план([полный], гит=сам.другой_снимок)["состояние"], "не готов")
        сам.assertEqual(сам.план([полный], вход=сам.другое_содержимое)["состояние"], "не готов")
        сам.assertEqual(сам.план([полный, запись(2)])["состояние"], "не готов")
        активная = запись(2)[1]
        активная["состояние"] = "выполняется"
        for поле in ("статус", "код_завершения", "длительность_наносекунды", "пояснение"):
            активная[поле] = None
        сам.assertFalse(сам.план([полный, упаковать(активная)])["доказанные_условия"]["нет_активных"])

    def test_локализация_связана_с_предыдущим_отказом_и_обоими_отпечатками(сам):
        отказ = сам.отказ(запись(1, "полная"))
        диагностика = запись(2, "диагностическая")[1]
        диагностика["профиль_проверки"].update({"основание": "локализация_наблюдаемого_отказа", "идентификатор_отказа": отказ[1]["идентификатор"]})
        финал = запись(3, "полная", отпечаток=сам.другое_содержимое)
        сам.assertEqual(сам.план([отказ, упаковать(диагностика), финал], вход=сам.другое_содержимое)["состояние"], "готов")
        for поле in ("содержимое", "гит", "идентификатор"):
            неверная = copy.deepcopy(диагностика)
            if поле == "содержимое":
                неверная["отпечаток_содержимого"] = сам.другое_содержимое
            elif поле == "гит":
                неверная["профиль_проверки"]["отпечаток_снимка"] = сам.другой_снимок
            else:
                неверная["профиль_проверки"]["идентификатор_отказа"] = финал[1]["идентификатор"]
            with сам.subTest(поле=поле):
                сам.assertEqual(сам.план([отказ, упаковать(неверная), финал], вход=сам.другое_содержимое)["состояние"], "не готов")

    def test_перекрытия_и_неуспешная_непокрытая_диагностика_не_скрываются(сам):
        диагностика = запись(1, "диагностическая")[1]
        финал = запись(2, "полная")
        сам.assertEqual(сам.план([упаковать(диагностика), финал])["состояние"], "не готов")
        диагностика["профиль_проверки"]["полные_наборы"] = ["Инструменты/fum-other/tests"]
        сам.assertEqual(сам.план([упаковать(диагностика), финал])["состояние"], "готов")
        сам.assertEqual(сам.план([сам.отказ(упаковать(диагностика)), финал])["состояние"], "не готов")
        история = [запись(1, "диагностическая"), финал, запись(3, "полная", отпечаток=сам.другое_содержимое)]
        сам.assertEqual(сам.план(история, вход=сам.другое_содержимое)["состояние"], "не готов")

    def test_старый_префикс_сохраняется_и_его_нарушения_не_стираются(сам):
        история = ТестыГраницыРаундов().история()

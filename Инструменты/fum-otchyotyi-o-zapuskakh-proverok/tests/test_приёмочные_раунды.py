        история[0] = запись(1, "полная", версия=3)
        история[2][1]["переход_схемы"] = переход(история[:2])
        история[2] = упаковать(история[2][1])
        итог = сам.план(история)
        сам.assertEqual(итог["состояние"], "не готов")
        сам.assertFalse(итог["доказанные_условия"]["исторические_нарушения_отсутствуют"])





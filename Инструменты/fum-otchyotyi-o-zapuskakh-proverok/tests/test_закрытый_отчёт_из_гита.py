    def test_пустой_вложенный_каталог_гита_не_исчезает_из_инвентаря(сам):
        def записать_дерево(байты):
            return subprocess.run(["git", "-C", str(сам.корень), "mktree", "-z"], input=байты, check=True, capture_output=True).stdout.strip().decode()

        пустое = записать_дерево(b"")
        части = сам.фикстура.каталог_записей.relative_to(сам.корень).parts + ("пустой",)

        def добавить(дерево, остаток):
            if not остаток:
                return пустое
            записи = [строка for строка in сам.гит("ls-tree", "-z", дерево).split(b"\0") if строка]
            имя = остаток[0].encode()
            for номер, строка in enumerate(записи):
                метаданные, путь = строка.split(b"\t", 1)
                if путь == имя:
                    объект = добавить(метаданные.split()[2].decode(), остаток[1:])
                    записи[номер] = b"040000 tree " + объект.encode() + b"\t" + имя
                    break
            else:
                сам.assertEqual(len(остаток), 1)
                записи.append(b"040000 tree " + пустое.encode() + b"\t" + имя)
            return записать_дерево(b"\0".join(записи) + b"\0")

        дерево = добавить(сам.гит("rev-parse", сам.коммит + "^{tree}").strip().decode(), части)
        родитель = сам.гит("rev-parse", сам.коммит + "^").strip().decode()
        коммит = сам.гит("commit-tree", дерево, "-p", родитель, "-m", "Скрытый пустой каталог").strip().decode()
        with сам.assertRaises(сам.модуль.ОшибкаОтчёта):
            сам.модуль.проверить_отчёт_в_коммите(сам.корень, коммит, путь_запроса)

    def test_тег_на_верный_блоб_не_подменяет_тип_объекта(сам):
        относительный = сам.фикстура.отчёт.relative_to(сам.корень).as_posix()
        объект = сам.гит("rev-parse", f"{сам.коммит}:{относительный}").decode().strip()
        данные_тега = f"object {объект}\ntype blob\ntag wrapped-report\ntagger FUM Tests <fum-tests@example.invalid> 1 +0000\n\nWrapped report\n".encode()
        тег = subprocess.run(["git", "-C", str(сам.корень), "hash-object", "-t", "tag", "-w", "--stdin"], input=данные_тега, capture_output=True, check=True).stdout.strip().decode()

        def подменить(дерево, части):
            записи = [строка for строка in сам.гит("ls-tree", "-z", дерево).split(b"\0") if строка]
            сырые = []
            for строка in записи:
                метаданные, имя = строка.split(b"\t", 1)
                режим, тип, объект = метаданные.split()
                if имя.decode() == части[0]:
                    объект = (тег if len(части) == 1 else подменить(объект.decode(), части[1:])).encode()
                сырые.append(режим.lstrip(b"0") + b" " + имя + b"\0" + bytes.fromhex(объект.decode()))
            return subprocess.run(["git", "-C", str(сам.корень), "hash-object", "--literally", "-t", "tree", "-w", "--stdin"], input=b"".join(сырые), capture_output=True, check=True).stdout.strip().decode()

        дерево = подменить(сам.гит("rev-parse", сам.коммит + "^{tree}").strip().decode(), Path(относительный).parts)
        родитель = сам.гит("rev-parse", сам.коммит + "^").strip().decode()
        коммит = сам.гит("commit-tree", дерево, "-p", родитель, "-m", "Тег вместо blob").strip().decode()
        with сам.assertRaises(сам.модуль.ОшибкаОтчёта):
            сам.модуль.проверить_отчёт_в_коммите(сам.корень, коммит, путь_запроса)

    def test_пакет_сохраняет_двоичные_байты_и_отклоняет_нарушения_протокола(сам):
        первый, второй = "a" * 40, "b" * 40
        полезные = b"\x00\n\xff"
        пакет = первый.encode() + b" blob 0\n\n" + второй.encode() + b" blob 3\n" + полезные + b"\n"
        итог = сам.модуль.разобрать_пакет_объектов([первый, второй], пакет)
        сам.assertEqual(итог, {первый: b"", второй: полезные})
        нарушения = (
            пакет[:-1], пакет + b"extra", пакет.replace(b" blob 0", b" tag 0", 1),
            пакет.replace(первый.encode(), b"c" * 40, 1),
            пакет.replace(b" blob 3", b" blob -3"), пакет.replace(b" blob 3", b" blob x"),
            пакет.replace(b" blob 3", b" blob 4"), пакет.replace(b" blob 3", b" blob 2"),
            первый.encode() + b" missing\n", пакет.split(b"\n", 1)[0],
            пакет.replace(первый.encode(), первый[:8].encode(), 1),
            пакет.replace(b" blob 0\n\n", b" blob 0\n!", 1),
            второй.encode() + b" blob 0\n\n" + первый.encode() + b" blob 0\n\n",
        )
        for номер, байты in enumerate(нарушения):
            with сам.subTest(случай=номер), сам.assertRaises(сам.модуль.ОшибкаОтчёта):
                сам.модуль.разобрать_пакет_объектов([первый, второй], байты)
        with сам.assertRaises(сам.модуль.ОшибкаОтчёта):
            сам.модуль.разобрать_пакет_объектов([первый, первый], пакет)


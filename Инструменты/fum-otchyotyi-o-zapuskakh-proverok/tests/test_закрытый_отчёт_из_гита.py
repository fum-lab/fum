def путь_проверяемой_реализации(путь: Path) -> Path:
    выбранный = os.environ.get("FUM_CHECKED_CODE_ROOT")
    if выбранный is None:
        return путь
    if not выбранный or not Path(выбранный).is_absolute():
        raise ValueError("корень проверяемой реализации должен быть явным абсолютным путём")
    return Path(выбранный) / путь.relative_to(Path(__file__).resolve().parents[3])


сценарии = путь_проверяемой_реализации(Path(__file__).resolve().parents[1] / "scripts")


class ТестыЧтенияЗакрытогоОтчёта(unittest.TestCase):
    def setUp(сам):
        изоляция = mock.patch.dict(os.environ, {"GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull})
        изоляция.start()
        сам.addCleanup(изоляция.stop)
        сам.фикстура = ФикстураОтчётов()
        сам.addCleanup(сам.фикстура.очистить)
        сам.корень = сам.фикстура.корень
        путь = сам.корень / "Инструменты/fum-kompleksnaya-proverka-repozitoriya/scripts/run-smoke-check.py"
        путь.parent.mkdir(parents=True)
        путь.write_text('''import json, os
from pathlib import Path
план = [{"ключ_проверки": "Инструменты/пример/tests", "название": "Проверка фикстуры"}]
значение = {"схема": "fum.smoke-test-observations.v1", "идентификатор_запуска": os.environ["FUM_CHECK_RUN_ID"], "текущая_проверка": None, "план": план, "наблюдения": [{**план[0], "статус": "успешно", "длительность_наносекунды": 1}]}
Path(os.environ["FUM_CHECK_RUN_OBSERVATIONS_PATH"]).write_text(json.dumps(значение, ensure_ascii=False, sort_keys=True, indent=2) + "\\n")
''')
        (сам.корень / "результат.bin").write_bytes(bytes(range(256)))
        сам.гит("add", ".")
        сам.идентификатор = "00000000-0000-4000-8000-000000000111"
        итог = сам.фикстура.запустить(сам.идентификатор, sys.executable, str(путь))
        сам.assertEqual(итог.returncode, 0, итог.stderr)
        итог = сам.фикстура.выполнить("закрыть")
        сам.assertEqual(итог.returncode, 0, итог.stderr)
        сам.гит("add", ".")
        сам.гит("commit", "-qm", "Принятый этап фикстуры")
        сам.коммит = сам.гит("rev-parse", "HEAD").decode().strip()
        сам.файлы = {путь.name: путь.read_bytes() for путь in сам.фикстура.каталог_записей.iterdir()}
        сам.отчёт = сам.фикстура.отчёт.read_bytes()
        сам.имя = next(имя for имя in сам.файлы if имя != "снимок.json")
        sys.path.insert(0, str(сценарии))
        сам.addCleanup(sys.path.remove, str(сценарии))
        описание = importlib.util.spec_from_file_location("чтение_отчёта", сценарии / "закрытый_отчёт_из_гита.py")
        сам.модуль = importlib.util.module_from_spec(описание)
        описание.loader.exec_module(сам.модуль)

    def гит(сам, *аргументы):
        return subprocess.run(["git", "-C", str(сам.корень), *аргументы], check=True, capture_output=True).stdout

    def байты(сам, файлы=None, отчёт=None, запрос=путь_запроса):
        return сам.модуль.проверить_байты_закрытого_отчёта(запрос, сам.отчёт if отчёт is None else отчёт, сам.файлы if файлы is None else файлы)

    def test_действительный_отчёт_реальной_обёртки(сам):
        итог = сам.байты()
        сам.assertEqual(итог["финальный_запуск"], сам.идентификатор)
        сам.assertEqual(итог["запусков"], 1)
        сам.assertEqual(итог["состояние"], "проверен")

    def test_неизвестные_лишние_и_исчезнувшие_записи(сам):
        for имя in ("неизвестно.json", "возобновление.json", "вложенный/запись.json"):
            with сам.subTest(имя=имя), сам.assertRaises(сам.модуль.ОшибкаОтчёта):
                сам.байты({**сам.файлы, имя: b"{}\n"})
        for имя in сам.файлы:
            with сам.subTest(убрано=имя), сам.assertRaises(сам.модуль.ОшибкаОтчёта):
                сам.байты({ключ: значение for ключ, значение in сам.файлы.items() if ключ != имя})

    def test_повторные_ключи_и_нечисловые_константы(сам):
        for имя in сам.файлы:
            исходные = сам.файлы[имя]
            значение = json.loads(исходные)
            ключ = next(iter(значение))
            дубль = json.dumps(ключ, ensure_ascii=False).encode() + b":" + json.dumps(значение[ключ], ensure_ascii=False).encode() + b","
            for байты in (исходные.replace(b"{", b"{" + дубль, 1), '{"нечисло":NaN}'.encode()):
                with сам.subTest(имя=имя), сам.assertRaises(сам.модуль.ОшибкаОтчёта):
                    сам.байты({**сам.файлы, имя: байты})

    def test_подмена_маркера_блока_и_чужой_запрос(сам):
        for отчёт in (сам.отчёт.replace(b"sha256:", b"sha256:0", 1), сам.отчёт.replace("успешно".encode(), "неуспешно".encode(), 1)):
            with сам.assertRaises(сам.модуль.ОшибкаОтчёта):
                сам.байты(отчёт=отчёт)
        with сам.assertRaises(сам.модуль.ОшибкаОтчёта):
            сам.байты(запрос="Журнал/другая-сессия/запрос.md")

    def test_изменение_снимка_записи_и_неканонические_байты(сам):
        for имя in сам.файлы:
            with сам.subTest(имя=имя), сам.assertRaises(сам.модуль.ОшибкаОтчёта):
                сам.байты({**сам.файлы, имя: сам.файлы[имя] + b" "})
            значение = json.loads(сам.файлы[имя])
            значение["лишнее"] = True
            with сам.assertRaises(сам.модуль.ОшибкаОтчёта):
                сам.байты({**сам.файлы, имя: json.dumps(значение).encode()})

    def test_чтение_исторического_коммита_без_изменения_рабочих_файлов(сам):
        сам.фикстура.отчёт.write_bytes(b"broken live report")
        (сам.фикстура.каталог_записей / "снимок.json").unlink()
        (сам.фикстура.каталог_записей / сам.имя).write_bytes(b"broken live record")
        (сам.корень / "результат.bin").write_bytes(b"local dirty")
        (сам.корень / "неотслеживаемый").write_text("Сохранить")
        сам.гит("update-index", "--assume-unchanged", "результат.bin")
        до = {путь.relative_to(сам.корень).as_posix(): (путь.read_bytes(), путь.stat().st_mode) for путь in сам.корень.rglob("*") if путь.is_file()}
        итог = сам.модуль.проверить_отчёт_в_коммите(сам.корень, сам.коммит, путь_запроса)
        после = {путь.relative_to(сам.корень).as_posix(): (путь.read_bytes(), путь.stat().st_mode) for путь in сам.корень.rglob("*") if путь.is_file()}
        сам.assertEqual(до, после)
        сам.assertEqual(итог["связь"]["состояние"], "подтверждён")
        сам.assertFalse(итог["завершение_обязательства_доказано"])

    def пересобрать(сам, значения, отпечаток=None):
        отчёты = importlib.import_module("отчёты_о_запусках_проверок")
        записи = []
        файлы = {}
        for значение in sorted(значения, key=lambda запись: запись["порядок"]):
            имя = str(значение["порядок"]) + "_" + значение["идентификатор"] + ".json"
            байты = отчёты.канонические_машинные_байты(значение)
            файлы[имя] = байты
            записи.append((Path(имя), значение, байты))
        отпечаток = отпечаток or json.loads(сам.файлы["снимок.json"])["отпечаток_закрытия"]
        снимок = отчёты.канонические_машинные_байты(отчёты.ожидаемый_снимок(записи, путь_запроса, отпечаток))
        файлы["снимок.json"] = снимок
        блок = отчёты.сформировать_блок(записи, отчёты.сформировать_закрытый_маркер(снимок), отпечаток)
        return файлы, отчёты.заменить_управляемый_блок_в_байтах(сам.отчёт, блок)

    def test_согласованный_снимок_без_приёмки_не_принимается(сам):
        основа = json.loads(сам.файлы[сам.имя])
        адресная = copy.deepcopy(основа)
        адресная.update({"план": None, "наблюдения": []})
        адресная["профиль_проверки"].update({"класс": "адресная", "полные_наборы": []})
        отказ = copy.deepcopy(основа)
        отказ.update({"статус": "неуспешно", "код_завершения": 1})
        отказ["наблюдения"][0]["статус"] = "неуспешно"
        хвост = copy.deepcopy(адресная)
        хвост.update({"порядок": 2, "идентификатор": "00000000-0000-4000-8000-000000000112"})
        лишнее = copy.deepcopy(основа)
        лишнее["недопустимое_поле"] = 1
        случаи = (([адресная], None), ([отказ], None), ([основа, хвост], None), ([основа], "sha256:" + "b" * 64), ([лишнее], None))
        for значения, отпечаток in случаи:
            файлы, отчёт = сам.пересобрать(значения, отпечаток)
            with сам.subTest(значения=значения, отпечаток=отпечаток), сам.assertRaises(сам.модуль.ОшибкаОтчёта):
                сам.байты(файлы, отчёт)


import json
import importlib.util
import os
import subprocess
import sys
import unittest
from pathlib import Path
from unittest import mock

import test_отчёты_о_запусках_проверок as исходный


class ТестыАдресногоОтложенияПроекции(unittest.TestCase):
    def setUp(сам):
        сам.модуль = исходный.загрузить_модуль_автоматизации()
        сам.фикстура = исходный.ФикстураОтчётов()
        сам.addCleanup(сам.фикстура.очистить)
        сам.скрипт = сам.фикстура.корень / сам.модуль.ПУТЬ_ПОЛНОЙ_ПРОВЕРКИ
        сам.скрипт.parent.mkdir(parents=True)

    def команда(сам, *хвост):
        return [sys.executable, "-B", str(сам.скрипт), *хвост]

    def test_оба_написания_флага_не_дают_полного_класса(сам):
        for хвост in [("--проекция", "отложена"), ("--проекция=отложена",)]:
            with сам.subTest(хвост=хвост):
                сам.assertFalse(сам.модуль.является_запуском_полной_проверки(
                    сам.фикстура.корень, сам.команда(*хвост)))
        сам.assertTrue(сам.модуль.является_запуском_полной_проверки(
            сам.фикстура.корень, сам.команда("--проекция", "активна")))

    def test_отложенный_процесс_не_наследует_полномочия_полной_приёмки(сам):
        сам.скрипт.write_text("import os, sys\n"
            "assert 'FUM_CHECK_RUN_ID' not in os.environ\n"
            "assert 'FUM_CHECK_RUN_OBSERVATIONS_PATH' not in os.environ\n"
            "raise SystemExit(4)\n", encoding="utf-8")
        with mock.patch.dict(os.environ, {"FUM_CHECK_RUN_ID": "чужой",
                                         "FUM_CHECK_RUN_OBSERVATIONS_PATH": "чужой"}):
            код = сам.модуль.выполнить_запуск(сам.фикстура.корень,
                Path(исходный.путь_запроса), "Частичный контур", "Codex", None, 10,
                сам.команда("--проекция", "отложена"), класс_проверки="адресная",
                приёмочные_раунды=True)
        сам.assertEqual(код, 4)
        записи = [json.loads(п.read_bytes()) for п in сам.фикстура.каталог_записей.glob("*.json")]
        сам.assertEqual(len(записи), 1)
        сам.assertEqual(записи[0]["схема"], "fum.test-run.v4")
        сам.assertEqual(записи[0]["профиль_проверки"]["класс"], "адресная")
        сам.assertIsNone(записи[0]["план"])
        сам.assertEqual(записи[0]["наблюдения"], [])

    def test_полный_класс_отложения_отвергается_до_записи_и_процесса(сам):
        with mock.patch.object(сам.модуль.subprocess, "Popen") as процесс:
            with сам.assertRaisesRegex(сам.модуль.ОшибкаОтчёта, "класс.*полная"):
                сам.модуль.выполнить_запуск(сам.фикстура.корень,
                    Path(исходный.путь_запроса), "Недопустимая приёмка", "Codex", None, 10,
                    сам.команда("--проекция=отложена"), класс_проверки="полная",
                    приёмочные_раунды=True)
        процесс.assert_not_called()
        сам.assertFalse(сам.фикстура.каталог_записей.exists())

    def test_неоднозначные_флаги_не_занимают_полную_попытку(сам):
        for хвост in [("--проекция", "отложена", "--проекция", "активна"),
                      ("--прое", "отложена"), ("--проекция", "неизвестна")]:
            with сам.subTest(хвост=хвост):
                сам.assertFalse(сам.модуль.является_запуском_полной_проверки(
                    сам.фикстура.корень, сам.команда(*хвост)))

    def test_основание_со_словом_отложена_не_заменяет_режим(сам):
        for хвост in [("--основание-отложения-проекции", "отложена"),
                      ("--осно", "отложена"),
                      ("--проекция", "активна", "--основание-отложения-проекции", "отложена")]:
            with сам.subTest(хвост=хвост):
                сам.assertTrue(сам.модуль.является_неполной_проверкой_проекции(
                    сам.фикстура.корень, сам.команда(*хвост)))
                сам.assertFalse(сам.модуль.является_запуском_полной_проверки(
                    сам.фикстура.корень, сам.команда(*хвост)))

    def test_неподдержанный_исполнитель_отвергнут_до_процесса_и_записи(сам):
        for префикс in [(sys.executable, "-X", "dev"), (sys.executable, "-Bu"),
                        ("env", sys.executable)]:
            команда = [*префикс, str(сам.скрипт), "--проекция", "отложена",
                       "--основание-отложения-проекции", "Пауза пользователя"]
            with сам.subTest(префикс=префикс), mock.patch.object(сам.модуль.subprocess, "Popen") as процесс:
                with сам.assertRaisesRegex(сам.модуль.ОшибкаОтчёта, "неподдержан"):
                    сам.модуль.выполнить_запуск(сам.фикстура.корень,
                        Path(исходный.путь_запроса), "Неподдержанный исполнитель", "Codex", None, 10,
                        команда, класс_проверки="адресная", приёмочные_раунды=True)
                процесс.assert_not_called()
                сам.assertFalse(сам.фикстура.каталог_записей.exists())

    def test_настоящая_обёртка_и_исполнитель_сохраняют_проекцию_и_следующую_полную_попытку(сам):
        путь_фикстуры = исходный.путь_проверяемой_реализации(
            Path(__file__).resolve().parents[2] /
            "fum-kompleksnaya-proverka-repozitoriya/tests/test_run_smoke_check.py")
        спецификация = importlib.util.spec_from_file_location("фикстура_отложенной_проекции", путь_фикстуры)
        фикстура = importlib.util.module_from_spec(спецификация)
        спецификация.loader.exec_module(фикстура)
        помощник = фикстура.RunSmokeCheckTests()
        помощник.write_script_fixture(сам.фикстура.корень)
        помощник.создать_фикстуры_документационных_тестов(сам.фикстура.корень)
        сам.скрипт.write_bytes(фикстура.SCRIPT_PATH.read_bytes())
        канарейка = сам.фикстура.корень / "Proyekcii/неизменный.bin"
        канарейка.parent.mkdir()
        канарейка.write_bytes(b"unchanged\x00\xff")
        команда = сам.команда("--repo-root", str(сам.фикстура.корень), "--skip-session-coherence")
        чужой_конверт = сам.фикстура.корень / "чужой-конверт.json"
        чужой_конверт.write_bytes(b"foreign envelope\n")
        with mock.patch.dict(os.environ, {"FUM_CHECK_RUN_ID": "чужой",
                  "FUM_CHECK_RUN_OBSERVATIONS_PATH": str(чужой_конверт)}):
            код = сам.модуль.выполнить_запуск(сам.фикстура.корень,
                Path(исходный.путь_запроса), "Частичная реальная фикстура", "Codex", None, 30,
                [*команда, "--проекция", "отложена", "--основание-отложения-проекции", "Пауза пользователя"],
                класс_проверки="адресная", приёмочные_раунды=True)
        сам.assertEqual(код, 4)
        сам.assertEqual(канарейка.read_bytes(), b"unchanged\x00\xff")
        сам.assertEqual(чужой_конверт.read_bytes(), b"foreign envelope\n")
        код = сам.модуль.выполнить_запуск(сам.фикстура.корень,
            Path(исходный.путь_запроса), "Следующая полная реальная фикстура", "Codex", None, 30,
            команда, класс_проверки="полная")
        сам.assertEqual(код, 0)
        записи = sorted((json.loads(п.read_bytes()) for п in сам.фикстура.каталог_записей.glob("*.json")),
                         key=lambda з: з["порядок"])
        сам.assertEqual([з["профиль_проверки"]["класс"] for з in записи], ["адресная", "полная"])
        сам.assertEqual(записи[0]["отпечаток_содержимого"], записи[1]["отпечаток_содержимого"])


if __name__ == "__main__":
    unittest.main()

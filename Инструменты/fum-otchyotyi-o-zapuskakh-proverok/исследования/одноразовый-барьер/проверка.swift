import Darwin
import Foundation

private enum ОшибкаПроверки: Error { case неудача(String) }

private func требовать(_ условие: @autoclosure () -> Bool, _ имя: String) throws {
    if !условие() { throw ОшибкаПроверки.неудача(имя) }
}

private func вывести(_ сообщение: String) {
    let байты = Array((сообщение + "\n").utf8)
    let результат = байты.withUnsafeBytes { write(STDOUT_FILENO, $0.baseAddress, $0.count) }
    if результат != байты.count { while true { pause() } }
}

private func каталог(_ родитель: Int32, _ имя: String) throws -> Int32 {
    guard имя.withCString({ mkdirat(родитель, $0, 0o700) }) == 0 else { throw ОшибкаБарьера("fixture-mkdir", errno) }
    let дескрипторКаталога = имя.withCString { openat(родитель, $0, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC) }
    guard дескрипторКаталога >= 0 else { throw ОшибкаБарьера("fixture-open", errno) }
    return дескрипторКаталога
}

private struct Фикстура {
    let опоры: ОпорыФикстуры
    let вторыеОпоры: ОпорыФикстуры

    init(дескрипторКорня: Int32, имя: String) throws {
        let основание = try каталог(дескрипторКорня, имя)
        let репозиторий = try каталог(основание, "repo")
        let сессия = try каталог(репозиторий, "session")
        let кореньРезерва = try каталог(основание, "reservations")
        let втораяСессия = "session".withCString {
            openat(репозиторий, $0, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        }
        guard втораяСессия >= 0 else { throw ОшибкаБарьера("fixture-second-session", errno) }
        опоры = try ОпорыФикстуры(дескрипторОснования: основание, дескрипторРепозитория: репозиторий, дескрипторСессии: сессия,
                               дескрипторКорняРезерва: кореньРезерва)
        вторыеОпоры = try ОпорыФикстуры(дескрипторОснования: основание, дескрипторРепозитория: репозиторий, дескрипторСессии: втораяСессия,
                                     дескрипторКорняРезерва: кореньРезерва)
    }

    func естьМаркер() -> Bool {
        var сведения = stat()
        return опоры.имяРезерва.withCString {
            fstatat(опоры.дескрипторКорняРезерва, $0, &сведения, AT_SYMLINK_NOFOLLOW)
        } == 0
    }
}

private final class ЧужойВызов: @unchecked Sendable {
    let барьер: БарьерФикстуры
    let дескрипторОтвета: Int32
    init(_ барьер: БарьерФикстуры, _ дескрипторОтвета: Int32) { self.барьер = барьер; self.дескрипторОтвета = дескрипторОтвета }
}

private func чужойВход(_ указатель: UnsafeMutableRawPointer) -> UnsafeMutableRawPointer? {
    let вызов = Unmanaged<ЧужойВызов>.fromOpaque(указатель).takeUnretainedValue()
    var байт: UInt8 = вызов.барьер.начать() == .отклонён ? 82 : 88
    _ = withUnsafePointer(to: &байт) { write(вызов.дескрипторОтвета, $0, 1) }
    return nil
}

private func вызватьИзДругогоПотока(_ барьер: БарьерФикстуры) throws -> ИсходБарьера? {
    var дескрипторы = [Int32](repeating: -1, count: 2)
    guard pipe(&дескрипторы) == 0 else { throw ОшибкаБарьера("thread-pipe", errno) }
    for дескрипторКанала in дескрипторы {
        guard fcntl(дескрипторКанала, F_SETFD, FD_CLOEXEC) == 0 else { throw ОшибкаБарьера("thread-pipe-cloexec", errno) }
        let флаги = fcntl(дескрипторКанала, F_GETFL)
        guard флаги >= 0, fcntl(дескрипторКанала, F_SETFL, флаги | O_NONBLOCK) == 0 else { throw ОшибкаБарьера("thread-pipe-nonblock", errno) }
    }
    // Поток перестаёт обращаться к барьеру до записи байта. Объект и pipe
    // сохраняются до _exit; получение байта не доказывает завершения потока.
    let вызов = ЧужойВызов(барьер, дескрипторы[1])
    let удержан = Unmanaged.passRetained(вызов).toOpaque()
    var поток: pthread_t?
    let создан = pthread_create(&поток, nil, чужойВход, удержан)
    guard создан == 0, поток != nil else { throw ОшибкаБарьера("thread-create", создан) }
    var ожидание = pollfd(fd: дескрипторы[0], events: Int16(POLLIN), revents: 0)
    let опрошено = poll(&ожидание, 1, 5_000)
    guard опрошено == 1, ожидание.revents & Int16(POLLIN) != 0 else {
        throw ОшибкаБарьера("thread-observe", опрошено < 0 ? errno : nil)
    }
    var байт: UInt8 = 0
    let прочитаноИзКанала = withUnsafeMutablePointer(to: &байт) { read(дескрипторы[0], $0, 1) }
    guard прочитаноИзКанала == 1 else { throw ОшибкаБарьера("thread-result", прочитаноИзКанала < 0 ? errno : nil) }
    return байт == 82 ? .отклонён : nil
}

@main private struct Испытание {
    static func main() {
        var фикстуры: [Фикстура] = []
        var барьеры: [БарьерФикстуры] = []
        var наблюдатели: [НаблюдательФикстуры] = []
        do {
            guard CommandLine.arguments.count == 2, CommandLine.arguments[1].hasPrefix("/") else {
                throw ОшибкаБарьера("argument")
            }
            let дескрипторКорня = CommandLine.arguments[1].withCString {
                open($0, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            }
            guard дескрипторКорня >= 0 else { throw ОшибкаБарьера("root-open", errno) }
            let корень = try ОпорыФикстуры.метка(дескрипторКорня)
            try требовать(корень.владелец == geteuid() && корень.права == 0o700, "root-identity")
            var начало = timespec()
            guard clock_gettime(CLOCK_MONOTONIC, &начало) == 0 else { throw ОшибкаБарьера("clock", errno) }
            let срок = начало.tv_sec + 30
            func проверитьСрок() throws {
                var сейчас = timespec()
                guard clock_gettime(CLOCK_MONOTONIC, &сейчас) == 0, сейчас.tv_sec < срок else {
                    throw ОшибкаБарьера("deadline")
                }
            }
            func фикстура(_ имя: String) throws -> Фикстура {
                try проверитьСрок()
                let созданная = try Фикстура(дескрипторКорня: дескрипторКорня, имя: имя)
                фикстуры.append(созданная)
                return созданная
            }
            func наблюдатель(_ фикстура: Фикстура) -> НаблюдательФикстуры {
                let значение = НаблюдательФикстуры(фикстура.вторыеОпоры)
                наблюдатели.append(значение)
                return значение
            }
            func отказано(_ наблюдатель: НаблюдательФикстуры, _ имя: String) throws {
                try требовать(наблюдатель.проверить() == .отказано, имя + "-result")
                try требовать(наблюдатель.фазаЗамка == "released", имя + "-release")
                try требовать(наблюдатель.событияНаблюдателя == ["lock", "observe", "verify-excl", "unlock"], имя + "-events")
                try требовать(наблюдатель.дескрипторНеожиданногоМаркера == -1, имя + "-no-create")
            }

            вывести("START ONE-SHOT-V2 PID \(getpid())")
            let обычная = try фикстура("normal")
            let выдаватель = ВыдавательФикстуры()
            let барьер = try выдаватель.выдать(обычная.опоры)
            барьеры.append(барьер)
            let чужойДоПуска = try вызватьИзДругогоПотока(барьер)
            try требовать(чужойДоПуска == .отклонён && барьер.состояние == .готов && барьер.событияБарьера.isEmpty,
                        "foreign-ready")
            try требовать(барьер.начать() == .допущен && барьер.состояние == .допущен, "admitted")
            let послеДопуска = барьер.событияБарьера
            try требовать(барьер.начать() == .отклонён && барьер.состояние == .допущен && барьер.событияБарьера == послеДопуска,
                        "duplicate-admitted")
            let чужойПослеДопуска = try вызватьИзДругогоПотока(барьер)
            try требовать(чужойПослеДопуска == .отклонён && барьер.состояние == .допущен && барьер.событияБарьера == послеДопуска,
                        "foreign-admitted")
            try требовать(барьер.закончить() == .закрыт && барьер.состояние == .закрыт, "closed")
            let послеЗакрытия = барьер.событияБарьера
            try требовать(барьер.начать() == .отклонён && барьер.закончить() == .отклонён &&
                        барьер.состояние == .закрыт && барьер.событияБарьера == послеЗакрытия, "duplicate-closed")
            try отказано(наблюдатель(обычная), "normal-observer")
            вывести("PASS duplicate-foreign")

            let неизвестно = try фикстура("unknown")
            let неизвестныйБарьер = try ВыдавательФикстуры().выдать(неизвестно.опоры, отказ: .передСозданием)
            барьеры.append(неизвестныйБарьер)
            try требовать(неизвестныйБарьер.начать() == .неизвестно && неизвестныйБарьер.состояние == .неизвестно,
                        "unknown-first")
            let перваяОшибка = неизвестныйБарьер.перваяПричина
            let первыеСобытия = неизвестныйБарьер.событияБарьера
            try требовать(перваяОшибка == ОшибкаБарьера("injected-beforeCreate") &&
                        неизвестныйБарьер.начать() == .отклонён && неизвестныйБарьер.закончить() == .отклонён &&
                        неизвестныйБарьер.состояние == .неизвестно && неизвестныйБарьер.перваяПричина == перваяОшибка &&
                        неизвестныйБарьер.событияБарьера == первыеСобытия && !неизвестно.естьМаркер(), "unknown-sticky")
            try требовать(наблюдатель(неизвестно).проверить() == .занято, "unknown-g-busy")
            вывести("PASS unknown-sticky")

            let неверныйФлаг = try фикстура("cloexec")
            let барьерНеверногоФлага = try ВыдавательФикстуры().выдать(неверныйФлаг.опоры)
            барьеры.append(барьерНеверногоФлага)
            guard fcntl(неверныйФлаг.опоры.дескрипторКорняРезерва, F_SETFD, 0) == 0 else { throw ОшибкаБарьера("fixture-flags", errno) }
            try требовать(барьерНеверногоФлага.начать() == .неизвестно && барьерНеверногоФлага.перваяПричина == ОшибкаБарьера("fd-cloexec"),
                        "cloexec-no-errno")
            try требовать(барьерНеверногоФлага.начать() == .отклонён && барьерНеверногоФлага.перваяПричина == ОшибкаБарьера("fd-cloexec"),
                        "cloexec-sticky")
            вывести("PASS cloexec-no-stale-errno")

            let сОстановкой = try фикстура("hook")
            let наблюдательЗанятости = наблюдатель(сОстановкой)
            var остановкаБыла = false
            let барьерСОстановкой = try ВыдавательФикстуры().выдать(сОстановкой.опоры, передОсвобождением: {
                guard наблюдательЗанятости.проверить() == .занято && наблюдательЗанятости.фазаЗамка == "not-held" &&
                      наблюдательЗанятости.событияНаблюдателя == ["lock"] else { throw ОшибкаБарьера("hook-not-busy") }
                остановкаБыла = true
            })
            барьеры.append(барьерСОстановкой)
            try требовать(барьерСОстановкой.начать() == .допущен && остановкаБыла && барьерСОстановкой.событияБарьера.contains("before-unlock"),
                        "hook-admit")
            try отказано(наблюдатель(сОстановкой), "hook-active")
            try требовать(барьерСОстановкой.закончить() == .закрыт, "hook-close")
            try отказано(наблюдатель(сОстановкой), "hook-closed")
            вывести("PASS hook-and-exclusive-observers")

            let ошибкаОстановки = try фикстура("hook-failure")
            let барьерОшибкиОстановки = try ВыдавательФикстуры().выдать(ошибкаОстановки.опоры, передОсвобождением: {
                throw ОшибкаБарьера("hook-failure", EIO)
            })
            барьеры.append(барьерОшибкиОстановки)
            try требовать(барьерОшибкиОстановки.начать() == .неизвестно && барьерОшибкиОстановки.состояние == .неизвестно &&
                        барьерОшибкиОстановки.перваяПричина == ОшибкаБарьера("hook-failure", EIO) &&
                        барьерОшибкиОстановки.фазаЗамка == "held" && ошибкаОстановки.естьМаркер(), "hook-failure")
            let событияОстановки = барьерОшибкиОстановки.событияБарьера
            try требовать(барьерОшибкиОстановки.начать() == .отклонён && барьерОшибкиОстановки.событияБарьера == событияОстановки &&
                        наблюдатель(ошибкаОстановки).проверить() == .занято, "hook-failure-holds")
            вывести("PASS hook-failure-holds")

            let подмена = try фикстура("post-hook-drift")
            let барьерПодмены = try ВыдавательФикстуры().выдать(подмена.опоры, передОсвобождением: {
                guard renameat(подмена.опоры.дескрипторОснования, "reservations", подмена.опоры.дескрипторОснования, "saved") == 0 else {
                    throw ОшибкаБарьера("fixture-rename", errno)
                }
                guard mkdirat(подмена.опоры.дескрипторОснования, "reservations", 0o700) == 0 else {
                    throw ОшибкаБарьера("fixture-replace", errno)
                }
            })
            барьеры.append(барьерПодмены)
            try требовать(барьерПодмены.начать() == .неизвестно && барьерПодмены.перваяПричина == ОшибкаБарьера("fixture-drift") &&
                        барьерПодмены.фазаЗамка == "held", "drift-unknown")
            let результатЗамка = flock(подмена.вторыеОпоры.дескрипторСессии, LOCK_EX | LOCK_NB)
            let ошибкаЗамка = результатЗамка == 0 ? 0 : errno
            try требовать(результатЗамка == -1 && (ошибкаЗамка == EWOULDBLOCK || ошибкаЗамка == EAGAIN), "drift-g-busy")
            вывести("PASS post-hook-drift")

            let неверныйДескриптор = try фикстура("bad-fd")
            let барьерНеверногоДескриптора = try ВыдавательФикстуры().выдать(неверныйДескриптор.опоры)
            барьеры.append(барьерНеверногоДескриптора)
            guard Darwin.close(неверныйДескриптор.опоры.дескрипторКорняРезерва) == 0 else { throw ОшибкаБарьера("fixture-close", errno) }
            try требовать(барьерНеверногоДескриптора.начать() == .неизвестно && барьерНеверногоДескриптора.перваяПричина == ОшибкаБарьера("fd-flags", EBADF),
                        "errno-first")
            try требовать(барьерНеверногоДескриптора.начать() == .отклонён && барьерНеверногоДескриптора.состояние == .неизвестно &&
                        барьерНеверногоДескриптора.перваяПричина == ОшибкаБарьера("fd-flags", EBADF), "errno-sticky")
            вывести("PASS errno-preserved")

            try проверитьСрок()
            try требовать(фикстуры.count == 7 && барьеры.count == 7 && наблюдатели.count == 6, "retained-count")
            вывести("TERMINAL 7 PASS")
            _exit(0)
        } catch {
            let имя: String
            if case ОшибкаПроверки.неудача(let значение) = error { имя = значение }
            else if let значение = error as? ОшибкаБарьера { имя = значение.фаза }
            else { имя = "unexpected" }
            вывести("HOLD " + имя)
            withExtendedLifetime((фикстуры, барьеры, наблюдатели)) { while true { pause() } }
        }
    }
}

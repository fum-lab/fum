@contextmanager
def стадия(имя):
    начало = perf_counter_ns()
    предки = СТЕК_ПРОФИЛЯ.get()
    токен = СТЕК_ПРОФИЛЯ.set((*предки, имя))
    исход = 'отказ'
    try:
        yield
        исход = 'успех'
    finally:
        СТЕК_ПРОФИЛЯ.reset(токен)
        try:
            print('FUM-PROFILE ' + канон.кодировать({'стадия':имя,'предки':list(предки),'длительность_нс':perf_counter_ns()-начало,'исход':исход}).decode().strip(), file=sys.stderr, flush=True)
        except (OSError, ValueError):
            pass


def безопасный_путь(путь, *, отсутствует=False):
    путь = Path(путь)
    требовать(путь.is_absolute() and str(путь) == os.path.normpath(str(путь)), 'Нужен канонический абсолютный путь')
    требовать(not any(ord(знак) < 32 or знак in '\\"\x7f' for знак in str(путь)), 'Небезопасное имя пути')
    текущий = Path(путь.anchor)
    for номер, часть in enumerate(путь.parts[1:]):
        имена = os.listdir(текущий)
        совпадения = [имя for имя in имена if unicodedata.normalize('NFC',имя).casefold() == unicodedata.normalize('NFC',часть).casefold()]
        if часть not in имена:
            требовать(отсутствует and номер == len(путь.parts)-2 and not совпадения, 'Путь отсутствует либо не совпадает регистр')
            return путь
        требовать(совпадения == [часть], 'Коллизия управляющего пути')
        текущий /= часть
        требовать(not текущий.is_symlink(), 'Symlink в управляющем пути')
    return путь


def прочитать_файл(путь):
    безопасный_путь(путь)
    with os.fdopen(os.open(путь,os.O_RDONLY|os.O_NOFOLLOW),'rb') as поток:
        до = os.fstat(поток.fileno())
        требовать(stat.S_ISREG(до.st_mode) and до.st_nlink == 1, 'Нужен обычный управляющий файл без hardlink')
        данные = поток.read()
        после = os.fstat(поток.fileno())
        требовать((до.st_dev,до.st_ino,до.st_size,до.st_mtime_ns) == (после.st_dev,после.st_ino,после.st_size,после.st_mtime_ns), 'Файл изменился при чтении')
        требовать(путь.stat().st_ino == до.st_ino, 'Файл заменён при чтении')
    return данные


def идентичность(путь):
    состояние = путь.stat()
    return канон.хэш(канон.кодировать([состояние.st_dev,состояние.st_ino]))


def относительный(имя):
    требовать(type(имя) is str and имя and not Path(имя).is_absolute() and all(часть not in ('','.','..') for часть in имя.split('/')), 'Неканонический относительный маршрут')
    требовать(not any(ord(знак)<32 or знак in '\\"\x7f' for знак in имя), 'Небезопасный маршрут')
    return имя


def привязать(привязки):
    канон.поля(привязки,('схема','владелец','источник','назначение','общий','состояние'))
    требовать(привязки['схема']=='fum.привязки-переноса.1','Неверная схема привязок')
    канон.идентификатор(привязки['владелец'])
    пути = {имя:безопасный_путь(привязки[имя],отсутствует=имя in ('источник','назначение')) for имя in ('источник','назначение','общий','состояние')}
    for имя in ('источник','назначение'):
        for другой in ('общий','состояние'):
            требовать(not пути[имя].is_relative_to(пути[другой]) and not пути[другой].is_relative_to(пути[имя]), 'Области дерева и метаданных пересекаются')
    требовать(not пути['источник'].is_relative_to(пути['назначение']) and not пути['назначение'].is_relative_to(пути['источник']), 'Источник и назначение пересекаются')
    требовать(not пути['состояние'].is_relative_to(пути['общий']) and not пути['общий'].is_relative_to(пути['состояние']), 'Приватное состояние пересекает Git common-dir')
    состояние = пути['состояние'].stat()
    требовать(stat.S_ISDIR(состояние.st_mode) and состояние.st_uid==os.getuid() and stat.S_IMODE(состояние.st_mode)==0o700, 'Состоянию нужен собственный каталог режима 0700')
    тома = {пути[имя].parent.stat().st_dev for имя in ('источник','назначение')}
    тома.update(пути[имя].stat().st_dev for имя in ('общий','состояние'))
    требовать(len(тома)==1,'Перенос между томами запрещён')
    требовать(sys.platform=='darwin' or sys.platform.startswith('linux'),'Платформа не поддержана')
    return пути


def гит(каталог, *аргументы, вход=None, коды=(0,)):
    среда = {ключ:значение for ключ,значение in os.environ.items() if not ключ.startswith('GIT_')}
    среда.update(GIT_NO_REPLACE_OBJECTS='1',GIT_NO_LAZY_FETCH='1',GIT_OPTIONAL_LOCKS='0',GIT_CONFIG_NOSYSTEM='1',GIT_CONFIG_GLOBAL=os.devnull,GIT_TERMINAL_PROMPT='0')
    ответ = subprocess.run(['git','-c','protocol.allow=never','-c','core.fsmonitor=false','-C',str(каталог),*аргументы],input=вход,env=среда,stdout=subprocess.PIPE,stderr=subprocess.PIPE,timeout=30)
    требовать(ответ.returncode in коды,'Git отказал: '+аргументы[0])
    return ответ.stdout


def конфигурация(каталог, данные):
    записи = гит(каталог,'config','--no-includes','--null','--file','-','--list',вход=данные).split(b'\0')
    требовать(записи.pop()==b'','Неверный вывод Git config')
    результат = {}
    for запись in записи:
        ключ, _, значение = запись.partition(b'\n')
        ключ = ключ.decode('utf-8')
        требовать(not ключ.startswith(('include.','includeif.')), 'Включения Git config не поддержаны')
        результат.setdefault(ключ,[]).append(значение.decode('utf-8'))
    return результат


def разрешить_ссылку(основание, значение):
    путь = Path(значение)
    return безопасный_путь(Path(os.path.normpath(str(путь if путь.is_absolute() else основание/путь))))


def прочитать_привязку(путь, префикс=b''):
    байты = прочитать_файл(путь)
    требовать(байты.startswith(префикс) and байты.endswith(b'\n') and b'\n' not in байты[:-1], 'Неверная Git-привязка')
    значение = байты[len(префикс):-1].decode('utf-8')
    требовать(bool(значение),'Пустая Git-привязка')
    return байты, значение


def значение_ссылки(старое, основание, цель):
    return str(цель) if Path(старое).is_absolute() else os.path.relpath(цель,основание)


def инвентарь(корень, исключения=(), *, служебный=False):
    результат = []
    имена = set()
    def обойти(каталог):
        for путь in sorted(каталог.iterdir()):
            имя = путь.relative_to(корень).as_posix()
            относительный(имя)
            ключ = unicodedata.normalize('NFC',имя).casefold()
            требовать(ключ not in имена,'Коллизия имён в дереве')
            имена.add(ключ)
            состояние = путь.lstat()
            режим = stat.S_IMODE(состояние.st_mode)
            требовать(состояние.st_dev == корень.stat().st_dev,'Вложенный том не поддержан')
            if имя in исключения:
                требовать(stat.S_ISREG(состояние.st_mode) and состояние.st_nlink==1,'Подменён управляющий файл')
                результат.append([имя,'управляемый',режим])
            elif stat.S_ISDIR(состояние.st_mode):
                требовать(путь.name.casefold() != '.git','Неучтённый вложенный репозиторий')
                результат.append([имя,'каталог',режим]); обойти(путь)
            elif stat.S_ISREG(состояние.st_mode):
                if служебный:
                    требовать(not путь.name.endswith('.lock') and not путь.name.startswith('sharedindex.'), 'Git lock или split index не поддержан')
                else:
                    требовать(путь.name.casefold() != '.git','Неучтённая Git-привязка')
                with путь.open('rb') as поток:
                    хэш = __import__('hashlib').file_digest(поток,'sha256').hexdigest()
                    после = os.fstat(поток.fileno())
                требовать((состояние.st_dev,состояние.st_ino,состояние.st_size,состояние.st_mtime_ns)==(после.st_dev,после.st_ino,после.st_size,после.st_mtime_ns),'Данные изменились при чтении')
                результат.append([имя,'файл',режим,состояние.st_size,хэш])
            elif stat.S_ISLNK(состояние.st_mode) and not служебный:
                результат.append([имя,'symlink',os.readlink(путь)])
            else:
                raise ValueError('Неподдержанный тип файла')
    обойти(корень)
    return канон.хэш(канон.кодировать([stat.S_IMODE(корень.stat().st_mode),результат]))


def изменить_рабочий_путь(данные, новое):
    строки = данные.splitlines(keepends=True)
    ядро = False
    найдено = 0
    for номер, строка in enumerate(строки):
        if строка.lstrip().startswith(b'['):
            ядро = re.fullmatch(rb'\s*\[core\]\s*',строка,re.IGNORECASE) is not None
        elif ядро and re.match(rb'\s*worktree\s*=',строка,re.IGNORECASE):
            совпадение = re.match(rb'(\s*worktree\s*=\s*)',строка,re.IGNORECASE)
            строки[номер] = совпадение.group(1)+b'"'+новое.encode('utf-8')+b'"\n'
            найдено += 1
    требовать(найдено==1,'Нужна единственная простая строка core.worktree')
    return b''.join(строки)


def собрать(привязки):
    пути = привязать(привязки)
    источник, назначение, общий = (пути[имя] for имя in ('источник','назначение','общий'))
    требовать(источник.is_dir() and not назначение.exists(),'Источник отсутствует либо назначение занято')
    требовать(источник.stat().st_dev==назначение.parent.stat().st_dev,'Перенос между томами запрещён')
    корневой_файл, ссылка = прочитать_привязку(источник/'.git',b'gitdir: ')
    административный = разрешить_ссылку(источник,ссылка)
    требовать(административный.parent == общий/'worktrees','Нужен один штатный linked worktree')
    владение = прочитать_файл(административный/'locked')
    требовать(владение==('fum-перенос:'+привязки['владелец']+'\n').encode(),'Нет подтверждения собственного владения worktree')
    _, обратная = прочитать_привязку(административный/'gitdir')
    требовать(разрешить_ссылку(административный,обратная)==источник/'.git','Несогласованная обратная Git-привязка')
    _, общий_адрес = прочитать_привязку(административный/'commondir')
    требовать(разрешить_ссылку(административный,общий_адрес)==общий,'Не совпадает common-dir')
    ремонт = []
    репозитории = []
    служебные_пути = set()

    def добавить(область, имя, до, после):
        путь = (источник if область=='дерево' else общий)/имя
        ремонт.append({'область':область,'путь':имя,'до':до.hex(),'после':после.hex(),'режим':stat.S_IMODE(путь.stat().st_mode)})

    добавить('общий',(административный/'gitdir').relative_to(общий).as_posix(),прочитать_файл(административный/'gitdir'),(значение_ссылки(обратная,административный,назначение/'.git')+'\n').encode())

    def репозиторий(рабочий, служебный, родитель=None, имя_секции=None):
        требовать(служебный.stat().st_dev==общий.stat().st_dev,'Git-метаданные на другом томе не поддержаны')
        относительный_корень = рабочий.relative_to(источник).as_posix()
        байты_привязки, ссылка = прочитать_привязку(рабочий/'.git',b'gitdir: ')
        требовать(разрешить_ссылку(рабочий,ссылка)==служебный,'Неверный Git-dir вложенного репозитория')
        требовать(str(служебный) not in служебные_пути,'Повторный Git-dir')
        служебные_пути.add(str(служебный))
        if родитель is not None:
            относительный(имя_секции)
            требовать(служебный == родитель / 'modules' / имя_секции and not (служебный/'commondir').exists(),'Нестандартная топология submodule')
        конфиг_путь = служебный/'config' if родитель is not None else общий/'config'
        конфиг = прочитать_файл(конфиг_путь)
        настройки = конфигурация(источник,конфиг)
        требовать('extensions.worktreeconfig' not in настройки and 'core.sparsecheckout' not in настройки and 'core.splitindex' not in настройки,'Worktree config, sparse и split index не поддержаны')
        объекты = ОбъектыГит(рабочий)
        требовать(Path(объекты.гит('rev-parse','--path-format=absolute','--git-common-dir').decode().strip())==(служебный if родитель is not None else общий),'Подменён common-dir репозитория')
        вершина = объекты.гит('rev-parse','--verify','HEAD').decode().strip()
        объекты.дерево_коммита(объекты.оид(вершина))
        сырой_указатель = прочитать_файл(служебный/'HEAD')
        ветка = гит(рабочий,'symbolic-ref','-q','HEAD',коды=(0,1)).decode().strip() or None
        требовать(родитель is not None or ветка is not None,'Linked корню нужна полная ветка')
        if ветка is not None:
            требовать(ветка.startswith('refs/heads/'),'HEAD не является веткой')
        индекс = прочитать_файл(служебный/'index')
        записи = объекты.гит('ls-files','--stage','-z').split(b'\0')
        требовать(записи.pop()==b'','Неверный индекс')
        вложенные = {}
        for запись in записи:
            свойства, имя = запись.split(b'\t',1)
            режим, ссылка_индекса, стадия_индекса = свойства.split(b' ')
            требовать(стадия_индекса==b'0' and режим!=b'040000','Конфликтный либо sparse index не поддержан')
            if режим==b'160000':
                вложенные[имя.decode('utf-8')]=ссылка_индекса.decode('ascii')
        репозитории.append({'путь':относительный_корень,'каталог_метаданных':служебный.relative_to(общий).as_posix(),'общий_каталог':'.' if родитель is None else служебный.relative_to(общий).as_posix(),'идентичность_метаданных':идентичность(служебный),'вершина':вершина,'ветка':ветка,'сырой_указатель':канон.хэш(сырой_указатель),'индекс':канон.хэш(индекс),'ссылки':канон.хэш(гит(рабочий,'for-each-ref','--format=%(refname) %(objectname)')) if родитель is not None else None})
        новое_дерево = назначение/относительный_корень
        добавить('дерево',(рабочий/'.git').relative_to(источник).as_posix(),байты_привязки,('gitdir: '+значение_ссылки(ссылка,новое_дерево,служебный)+'\n').encode())
        if родитель is not None:
            рабочие_пути = настройки.get('core.worktree',[])
            требовать(len(рабочие_пути)==1 and разрешить_ссылку(служебный,рабочие_пути[0])==рабочий,'Несогласованный core.worktree')
            после = изменить_рабочий_путь(конфиг,значение_ссылки(рабочие_пути[0],служебный,новое_дерево))
            изменённые = конфигурация(источник,после)
            требовать({ключ:значение for ключ,значение in настройки.items() if ключ!='core.worktree'}=={ключ:значение for ключ,значение in изменённые.items() if ключ!='core.worktree'},'Ремонт затрагивает чужую настройку')
            добавить('общий',конфиг_путь.relative_to(общий).as_posix(),конфиг,после)
        else:
            требовать('core.worktree' not in настройки,'Общий core.worktree не поддержан')
        модули = рабочий/'.gitmodules'
        описания = конфигурация(источник,прочитать_файл(модули)) if модули.exists() else {}
        пути_модулей = {}
        for ключ, значения in описания.items():
            требовать(ключ.startswith('submodule.'),'Неизвестная секция .gitmodules')
            if ключ.endswith('.path'):
                требовать(len(значения)==1,'Повтор пути submodule')
                путь = относительный(значения[0]); имя = ключ[len('submodule.'):-len('.path')]
                относительный(имя)
                требовать(путь not in пути_модулей,'Повторный путь submodule')
                пути_модулей[путь]=имя
        требовать(set(пути_модулей)==set(вложенные),'Gitlinks и .gitmodules не совпадают')
        for путь, имя in sorted(пути_модулей.items()):
            дочерний = безопасный_путь(рабочий/путь)
            требовать(дочерний.is_dir(),'Submodule не инициализирован')
            репозиторий(дочерний,безопасный_путь(служебный / 'modules' / имя),служебный,имя)

    репозиторий(источник,административный)
    исключения_дерева = [запись['путь'] for запись in ремонт if запись['область']=='дерево']
    исключения_метаданных = [str((общий/запись['путь']).relative_to(административный)) for запись in ремонт if запись['область']=='общий']
    тело = {'схема':'fum.план-переноса.1','владелец':привязки['владелец'],'привязки_sha256':канон.хэш(канон.кодировать(привязки)),'идентичность_дерева':идентичность(источник),'идентичность_общего':идентичность(общий),'идентичность_состояния':идентичность(пути['состояние']),'родители':[идентичность(источник.parent),идентичность(назначение.parent)],'репозитории':репозитории,'данные':инвентарь(источник,исключения_дерева),'метаданные':инвентарь(административный,исключения_метаданных,служебный=True),'общая_конфигурация':канон.хэш(прочитать_файл(общий/'config')),'ремонт':[{ключ:значение for ключ,значение in запись.items() if ключ not in ('до','после')} | {'до':канон.хэш(bytes.fromhex(запись['до'])),'после':канон.хэш(bytes.fromhex(запись['после']))} for запись in ремонт]}
    план = тело | {'операция':канон.хэш(канон.кодировать(тело))}
    return план,ремонт


def построить(привязки):
    with стадия('план'):
        return собрать(привязки)[0]


def сохранить(путь, данные, *, новый=False, режим=0o600):
    временный = путь.parent/'подготовка.tmp'
    if временный.exists():
        прочитать_файл(временный)
        временный.unlink()
    with os.fdopen(os.open(временный,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,режим),'wb') as поток:
        поток.write(данные); поток.flush(); os.fchmod(поток.fileno(),режим); os.fsync(поток.fileno())
    if новый:
        УСТОЙЧИВОСТЬ.переименовать_устойчиво_без_замены(временный,путь)
    else:
        os.replace(временный,путь)
        УСТОЙЧИВОСТЬ.синхронизировать_каталог(путь.parent)


def записать_состояние(путь, состояние, *, новый=False):
    данные = канон.кодировать(состояние)
    сохранить(путь,канон.кодировать({'данные':состояние,'sha256':канон.хэш(данные)}),новый=новый)


def адрес_ремонта(запись, дерево, общий):
    требовать(запись['область'] in ('дерево','общий'),'Неизвестная область ремонта')
    return безопасный_путь((дерево if запись['область']=='дерево' else общий)/относительный(запись['путь']))


def сверить(план, ремонт, пути, дерево, *, завершён=False):
    общий = пути['общий']
    требовать(идентичность(дерево)==план['идентичность_дерева'] and идентичность(общий)==план['идентичность_общего'] and идентичность(пути['состояние'])==план['идентичность_состояния'],'Изменена идентичность каталогов')
    требовать([идентичность(пути['источник'].parent),идентичность(пути['назначение'].parent)]==план['родители'],'Изменены родители маршрута')
    требовать(канон.хэш(прочитать_файл(общий/'config'))==план['общая_конфигурация'],'Изменена общая конфигурация')
    исключения_дерева = [запись['путь'] for запись in ремонт if запись['область']=='дерево']
    административный = общий/план['репозитории'][0]['каталог_метаданных']
    исключения_метаданных = [str((общий/запись['путь']).relative_to(административный)) for запись in ремонт if запись['область']=='общий']
    требовать(инвентарь(дерево,исключения_дерева)==план['данные'],'Изменены данные источника')
    требовать(инвентарь(административный,исключения_метаданных,служебный=True)==план['метаданные'],'Изменены индекс либо метаданные источника')
    for запись in ремонт:
        путь = адрес_ремонта(запись,дерево,общий)
        данные = прочитать_файл(путь)
        допустимые = [bytes.fromhex(запись['после'])] if завершён else [bytes.fromhex(запись[ключ]) for ключ in ('до','после')]
        требовать(данные in допустимые and stat.S_IMODE(путь.stat().st_mode)==запись['режим'],'Неожиданные байты Git-привязки')
    for репо in план['репозитории']:
        служебный = общий/репо['каталог_метаданных']
        требовать(идентичность(служебный)==репо['идентичность_метаданных'],'Подменён git-dir')
        # Явный --git-dir не требует работающей .git/core.worktree после rename.
        вершина = гит(общий,'--git-dir='+str(служебный),'--work-tree='+str(дерево/репо['путь']),'rev-parse','--verify','HEAD').decode().strip()
        требовать(вершина==репо['вершина'],'Изменился HEAD либо ref')
        ветка = гит(общий,'--git-dir='+str(служебный),'--work-tree='+str(дерево/репо['путь']),'symbolic-ref','-q','HEAD',коды=(0,1)).decode().strip() or None
        требовать(ветка==репо['ветка'],'Изменился полный ref')
        if репо['ссылки'] is not None:
            требовать(канон.хэш(гит(общий,'--git-dir='+str(служебный),'--work-tree='+str(дерево/репо['путь']),'for-each-ref','--format=%(refname) %(objectname)'))==репо['ссылки'],'Изменились refs submodule')
        if завершён:
            объекты = ОбъектыГит(дерево/репо['путь'])
            объекты.дерево_коммита(объекты.оид(репо['вершина']))
            требовать(Path(объекты.гит('rev-parse','--absolute-git-dir').decode().strip())==служебный,'Ремонт не восстановил git-dir')


def применить(план, привязки, владелец):
    with стадия('исполнение-или-возобновление'):
        пути = привязать(привязки)
        требовать(владелец==привязки['владелец']==план.get('владелец'),'Чужой владелец операции')
        требовать(канон.хэш(канон.кодировать(привязки))==план.get('привязки_sha256'),'Подменены привязки операции')
        тело = {ключ:значение for ключ,значение in план.items() if ключ!='операция'}
        требовать(канон.хэш(канон.кодировать(тело))==план.get('операция'),'Подменён план')
        каталог = пути['состояние']
        путь_состояния = каталог/'операция.json'
        замок = безопасный_путь(каталог/'операция.lock',отсутствует=True)
        with os.fdopen(os.open(замок,os.O_CREAT|os.O_RDWR|os.O_NOFOLLOW,0o600),'r+b') as поток:
            fcntl.flock(поток,fcntl.LOCK_EX|fcntl.LOCK_NB)
            требовать(поток.fileno()>=0 and os.fstat(поток.fileno()).st_nlink==1 and замок.stat().st_ino==os.fstat(поток.fileno()).st_ino,'Подменён постоянный замок')
            УСТОЙЧИВОСТЬ.синхронизировать_каталог(каталог)
            требовать(set(os.listdir(каталог)) <= {'операция.lock','операция.json','подготовка.tmp','готовые-байты'},'Неизвестное приватное состояние')
            if путь_состояния.exists():
                конверт = канон.прочитать(прочитать_файл(путь_состояния))
                канон.поля(конверт,('данные','sha256'))
                состояние = конверт['данные']
                требовать(канон.хэш(канон.кодировать(состояние))==конверт['sha256'],'Повреждено состояние')
                канон.поля(состояние,('схема','план','привязки','ремонт','фаза','номер_ремонта'))
                требовать(состояние['схема']=='fum.состояние-переноса.1' and состояние['план']==план and состояние['привязки']==привязки,'Сохранено другое намерение')
            else:
                требовать(not (каталог/'подготовка.tmp').exists() and not (каталог/'готовые-байты').exists(),'Незавершённая первичная запись состояния')
                with стадия('повторная-проверка-плана'):
                    фактический, ремонт = собрать(привязки)
                    требовать(фактический==план,'План устарел')
                состояние = {'схема':'fum.состояние-переноса.1','план':план,'привязки':привязки,'ремонт':ремонт,'фаза':'перемещение','номер_ремонта':0}
                записать_состояние(путь_состояния,состояние,новый=True)
            ремонт = состояние['ремонт']
            требовать(type(ремонт) is list and len(ремонт)==len(план['ремонт']),'Изменён перечень ремонта')
            for запись, ожидаемая in zip(ремонт,план['ремонт']):
                канон.поля(запись,('область','путь','до','после','режим'))
                сводка = {ключ:значение for ключ,значение in запись.items() if ключ not in ('до','после')} | {ключ:канон.хэш(bytes.fromhex(запись[ключ])) for ключ in ('до','после')}
                требовать(сводка==ожидаемая,'Ремонт подменяет исходный план')
            требовать(type(состояние['номер_ремонта']) is int and 0<=состояние['номер_ремонта']<=len(ремонт),'Неверная позиция ремонта')
            требовать(состояние['фаза'] in ('перемещение','ремонт','сверка','завершён'),'Неизвестная фаза')
            источник, назначение = пути['источник'],пути['назначение']
            требовать(источник.exists()!=назначение.exists(),'Неоднозначное положение каталога')
            дерево = источник if источник.exists() else назначение
            with стадия('сверка'):
                сверить(план,ремонт,пути,дерево,завершён=состояние['фаза']=='завершён')
            if состояние['фаза']=='завершён':
                требовать(not (каталог/'подготовка.tmp').exists() and not (каталог/'готовые-байты').exists(),'Лишний хвост завершённой операции')
                требовать(дерево==назначение,'Завершённый каталог находится не в назначении')
                return {'схема':'fum.результат-переноса.1','операция':план['операция'],'состояние':'завершён','репозитории':len(план['репозитории'])}
            if дерево==источник:
                требовать(состояние['фаза']=='перемещение','Фаза не допускает повторного перемещения')
                with стадия('переименование'):
                    контрольная_точка('до-перемещения')
                    УСТОЙЧИВОСТЬ.переименовать_устойчиво_без_замены(источник,назначение)
                    контрольная_точка('после-перемещения')
            # Повтор закрепляет эффект даже после отказа fsync исходного процесса.
            УСТОЙЧИВОСТЬ.синхронизировать_каталог(назначение.parent)
            УСТОЙЧИВОСТЬ.синхронизировать_каталог(источник.parent)
            if состояние['фаза']=='перемещение':
                состояние['фаза']='ремонт'
                записать_состояние(путь_состояния,состояние)
            контрольная_точка('после-фазы-ремонта')
            with стадия('ремонт'):
                for номер in range(состояние['номер_ремонта'],len(ремонт)):
                    запись = ремонт[номер]
                    # Намерение и текущий номер закреплены до подготовки байтов и замены.
                    сверить(план,ремонт,пути,назначение)
                    требовать(замок.stat().st_ino==os.fstat(поток.fileno()).st_ino,'Подменён постоянный замок')
                    путь = адрес_ремонта(запись,назначение,пути['общий'])
                    после = bytes.fromhex(запись['после'])
                    подготовка = каталог/'готовые-байты'
                    if подготовка.exists():
                        требовать(прочитать_файл(подготовка)==после and stat.S_IMODE(подготовка.stat().st_mode)==запись['режим'],'Подменены подготовленные байты')
                    if прочитать_файл(путь)!=после:
                        if not подготовка.exists():
                            сохранить(подготовка,после,новый=True,режим=запись['режим'])
                        контрольная_точка('после-подготовки-'+str(номер))
                        требовать(прочитать_файл(путь)==bytes.fromhex(запись['до']),'Изменены байты перед ремонтом')
                        os.replace(подготовка,путь)
                        контрольная_точка('после-замены-'+str(номер))
                    elif подготовка.exists():
                        подготовка.unlink()
                    # Повтор также закрепляет rename с потерянным результатом fsync.
                    УСТОЙЧИВОСТЬ.синхронизировать_каталог(путь.parent)
                    УСТОЙЧИВОСТЬ.синхронизировать_каталог(каталог)
                    состояние['номер_ремонта']=номер+1
                    записать_состояние(путь_состояния,состояние)
                    контрольная_точка('после-ремонта-'+str(номер))
            состояние['фаза']='сверка'
            записать_состояние(путь_состояния,состояние)
            контрольная_точка('до-сверки')
            with стадия('завершающая-сверка'):
                сверить(план,ремонт,пути,назначение,завершён=True)
            состояние['фаза']='завершён'
            записать_состояние(путь_состояния,состояние)
            контрольная_точка('после-завершения')
            return {'схема':'fum.результат-переноса.1','операция':план['операция'],'состояние':'завершён','репозитории':len(план['репозитории'])}


def главный():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('команда',choices=('план','применить'))
    парсер.add_argument('--привязки',required=True,type=Path)
    парсер.add_argument('--план',type=Path)
    парсер.add_argument('--владелец')
    параметры = парсер.parse_args()
    try:
        привязки = канон.прочитать(прочитать_файл(параметры.привязки.absolute()))
        if параметры.команда=='план':
            требовать(параметры.план is None and параметры.владелец is None,'План только читает привязки и пишет stdout')
            результат = построить(привязки)
        else:
            требовать(параметры.план is not None and параметры.владелец is not None,'Нужны сохранённый план и владелец')
            результат = применить(канон.прочитать(прочитать_файл(параметры.план.absolute())),привязки,параметры.владелец)
        sys.stdout.buffer.write(канон.кодировать(результат))
        return 0
    except (ValueError,OSError,subprocess.SubprocessError) as ошибка:
        print('Отказ переноса: '+str(ошибка),file=sys.stderr)
        return 2


if __name__=='__main__':
    raise SystemExit(главный())

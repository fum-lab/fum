"""Финализация контейнера сохраняет квитанции отдельных переносов."""
from pathlib import Path
import copy
import os
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch
from фикстуры import создать, гит, перенос, процесс, ВЛАДЕЛЕЦ, снимок_всего


def партия(основание, два=False):
    привязки = создать(основание, контейнер=True)
    план = перенос.построить(привязки)
    результат = перенос.применить(план, привязки, ВЛАДЕЛЕЦ)
    данные = {'схема':'fum.партия-переноса.1','операции':[{'план':план,'привязки':привязки}]}
    if два:
        второй = Path(привязки['источник']).parent/'второй'
        гит(основание/'главный','worktree','add','-b','codex/второй',str(второй))
        гит(второй,'submodule','update','--init','--recursive')
        гит(основание/'главный','worktree','lock','--reason','fum-перенос:'+ВЛАДЕЛЕЦ,str(второй))
        состояние = основание/'второе-состояние';состояние.mkdir(mode=0o700)
        привязки = привязки | {'источник':str(второй),'назначение':str(Path(привязки['назначение']).parent/'второй'),'состояние':str(состояние)}
        план = перенос.построить(привязки)
        перенос.применить(план,привязки,ВЛАДЕЛЕЦ)
        данные['операции'].append({'план':план,'привязки':привязки})
    return данные, результат


def завершение(путь, точка=''):
    код = """import sys,os
from pathlib import Path
sys.path.insert(0,sys.argv[1])
import перенос
def прервать(фаза):
 if фаза==sys.argv[3]:os._exit(77)
перенос.контрольная_точка=прервать
данные=перенос.канон.прочитать(Path(sys.argv[2]).read_bytes())
sys.stdout.buffer.write(перенос.канон.кодировать(перенос.завершить_контейнер(данные,sys.argv[4])))
"""
    return subprocess.run([sys.executable,'-B','-c',код,str(Path(перенос.__file__).parent),str(путь),точка,ВЛАДЕЛЕЦ],capture_output=True)


class ПроверкаКонтейнера(unittest.TestCase):
    def test_контейнер_удаляется_а_повтор_переноса_сохраняется(сам):
        for файл in (False,True):
            with сам.subTest(файл=файл), tempfile.TemporaryDirectory() as временный:
                основание = Path(временный).resolve()
                данные, квитанция = партия(основание)
                запись = данные['операции'][0]; привязки = запись['привязки']
                старый = Path(привязки['источник']).parent; новый = Path(привязки['назначение']).parent
                if файл:
                    (старый/'.DS_Store').write_bytes(b'finder\x00bytes')
                    номер = (старый/'.DS_Store').stat().st_ino
                первый = перенос.завершить_контейнер(данные,ВЛАДЕЛЕЦ)
                сам.assertFalse(старый.exists())
                if файл:
                    сам.assertEqual(b'finder\x00bytes',(новый/'.DS_Store').read_bytes())
                    сам.assertEqual(номер,(новый/'.DS_Store').stat().st_ino)
                сам.assertEqual(первый,перенос.завершить_контейнер(данные,ВЛАДЕЛЕЦ))
                сам.assertEqual(квитанция,перенос.применить(запись['план'],привязки,ВЛАДЕЛЕЦ))

    def test_новый_процесс_после_удаления_контейнера_завершает_ту_же_партию(сам):
        with tempfile.TemporaryDirectory() as временный:
            основание = Path(временный).resolve();данные,_ = партия(основание)
            путь = основание/'партия.json';путь.write_bytes(перенос.канон.кодировать(данные))
            первый = завершение(путь,'контейнер-после-удаления')
            сам.assertEqual(77,первый.returncode,первый.stderr.decode())
            повтор = завершение(путь)
            сам.assertEqual(0,повтор.returncode,повтор.stderr.decode())
            сам.assertEqual(повтор.stdout,завершение(путь).stdout)

    def test_частичное_намерение_и_перенос_файла_возобновляются(сам):
        for точка in ('контейнер-после-отметки-0','контейнер-после-намерения','контейнер-после-файла'):
            with сам.subTest(точка=точка), tempfile.TemporaryDirectory() as временный:
                основание = Path(временный).resolve(); данные,_ = партия(основание,два=True)
                старый = Path(данные['операции'][0]['привязки']['источник']).parent
                (старый/'.DS_Store').write_bytes(b'finder-data')
                путь = основание/'партия.json';путь.write_bytes(перенос.канон.кодировать(данные))
                первый = завершение(путь,точка)
                сам.assertEqual(77,первый.returncode,первый.stderr.decode())
                повтор = завершение(путь)
                сам.assertEqual(0,повтор.returncode,повтор.stderr.decode())
                сам.assertEqual(повтор.stdout,завершение(путь).stdout)
                for запись in данные['операции']:
                    сам.assertEqual('завершён',перенос.применить(запись['план'],запись['привязки'],ВЛАДЕЛЕЦ)['состояние'])

    def test_посторонние_объекты_и_неполная_партия_сохраняются_при_отказе(сам):
        for случай in ('неполная','дубль','неизвестный','занято','symlink','hardlink','подготовка','незавершённая'):
            with сам.subTest(случай=случай), tempfile.TemporaryDirectory() as временный:
                основание = Path(временный).resolve(); данные,_ = партия(основание,два=True)
                запись = данные['операции'][0]; привязки = запись['привязки']
                старый = Path(привязки['источник']).parent; новый = Path(привязки['назначение']).parent
                файл = старый/'.DS_Store';файл.write_bytes(b'finder-data')
                if случай=='неполная':данные['операции'].pop()
                if случай=='дубль':данные['операции'].append(copy.deepcopy(запись))
                if случай=='неизвестный':(старый/'чужой').write_bytes(b'keep')
                if случай=='занято':(новый/'.DS_Store').write_bytes(b'other')
                if случай in ('symlink','hardlink'):
                    файл.rename(основание/'оригинал')
                    if случай=='symlink':файл.symlink_to(основание/'оригинал')
                    else:os.link(основание/'оригинал',файл)
                if случай=='подготовка':(Path(привязки['состояние'])/'контейнер.tmp').write_bytes(b'partial')
                if случай=='незавершённая':
                    путь = Path(привязки['состояние'])/'операция.json'
                    состояние = перенос.прочитать_конверт(путь);состояние['фаза']='сверка'
                    путь.write_bytes(перенос.канон.кодировать({'данные':состояние,'sha256':перенос.канон.хэш(перенос.канон.кодировать(состояние))}))
                до = снимок_всего(старый),снимок_всего(новый)
                with сам.assertRaises((ValueError,OSError)):
                    перенос.завершить_контейнер(данные,ВЛАДЕЛЕЦ)
                сам.assertEqual(до,(снимок_всего(старый),снимок_всего(новый)))
                if случай=='подготовка':сам.assertEqual(b'partial',(Path(привязки['состояние'])/'контейнер.tmp').read_bytes())

    def test_после_удаления_нужны_повторная_синхронизация_и_неизменные_данные(сам):
        with tempfile.TemporaryDirectory() as временный:
            основание = Path(временный).resolve(); данные,_ = партия(основание)
            запись = данные['операции'][0]; привязки = запись['привязки']
            старый = Path(привязки['источник']).parent; новый = Path(привязки['назначение']).parent
            исходная = перенос.УСТОЙЧИВОСТЬ.синхронизировать_каталог
            def отказ(путь):
                if путь==старый.parent and not старый.exists():raise OSError('потеря синхронизации')
                return исходная(путь)
            with patch.object(перенос.УСТОЙЧИВОСТЬ,'синхронизировать_каталог',отказ), сам.assertRaises(OSError):
                перенос.завершить_контейнер(данные,ВЛАДЕЛЕЦ)
            сам.assertFalse(старый.exists())
            with patch.object(перенос.УСТОЙЧИВОСТЬ,'синхронизировать_каталог',wraps=исходная) as наблюдение:
                перенос.завершить_контейнер(данные,ВЛАДЕЛЕЦ)
                наблюдение.assert_any_call(старый.parent);наблюдение.assert_any_call(новый)
            файл = Path(привязки['назначение'])/'данные';исходные_байты = файл.read_bytes();файл.write_bytes(b'drift')
            with сам.assertRaises(ValueError):перенос.завершить_контейнер(данные,ВЛАДЕЛЕЦ)
            сам.assertEqual(b'drift',файл.read_bytes())
            файл.write_bytes(исходные_байты)
            старый.mkdir()
            with сам.assertRaises(ValueError):перенос.применить(запись['план'],привязки,ВЛАДЕЛЕЦ)

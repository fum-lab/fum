"""Явный пересмотр текущих данных сохраняет прерванный ремонт и старое свидетельство."""
from pathlib import Path
import copy
import os
import subprocess
import sys
import tempfile
import unittest
from фикстуры import подготовить, перенос, процесс, ВЛАДЕЛЕЦ, снимок_всего, снимок_репозиториев


def прервать(основание):
    привязки, план, путь, файл = подготовить(основание)
    исходные = снимок_репозиториев(Path(привязки['источник']))
    ответ = процесс(путь, файл, 'после-ремонта-1')
    if ответ.returncode != 77: raise AssertionError(ответ.stderr.decode())
    дерево = Path(привязки['назначение'])
    (дерево/'игнорируемый').write_bytes(b'latest\x00payload')
    return привязки, план, исходные


def принять_процессом(путь, привязки, точка=''):
    код = """import sys,os
from pathlib import Path
sys.path.insert(0,sys.argv[1])
import перенос
def прервать(фаза):
 if фаза==sys.argv[4]:os._exit(77)
перенос.контрольная_точка=прервать
кандидат=перенос.канон.прочитать(Path(sys.argv[2]).read_bytes())
привязки=перенос.канон.прочитать(Path(sys.argv[3]).read_bytes())
sys.stdout.buffer.write(перенос.канон.кодировать(перенос.принять_пересмотр(кандидат,привязки,sys.argv[5])))
"""
    return subprocess.run([sys.executable,'-B','-c',код,str(Path(перенос.__file__).parent),str(путь),str(привязки),точка,ВЛАДЕЛЕЦ],capture_output=True)


class ПроверкаПересмотра(unittest.TestCase):
    def test_новый_снимок_сохраняет_курсор_и_продолжает_ту_же_работу(сам):
        with tempfile.TemporaryDirectory() as временный:
            основание = Path(временный).resolve(); привязки,план,репо = прервать(основание)
            каталог = Path(привязки['состояние']); дерево = Path(привязки['назначение'])
            старые = (каталог/'операция.json').read_bytes()
            до = снимок_всего(основание)
            кандидат = перенос.пересмотреть(план,привязки,ВЛАДЕЛЕЦ)
            сам.assertEqual(до,снимок_всего(основание))
            сам.assertTrue(any(x[0]=='игнорируемый' for x in кандидат['инвентарь'][1]))
            новый = перенос.принять_пересмотр(кандидат,привязки,ВЛАДЕЛЕЦ)
            сам.assertEqual({'данные','операция'},{k for k in план if план[k]!=новый[k]})
            состояние = перенос.прочитать_конверт(каталог/'операция.json')
            прежнее = перенос.канон.прочитать(старые)['данные']
            сам.assertEqual(прежнее|{'план':новый},состояние)
            запись = перенос.прочитать_конверт(каталог/'пересмотр.json')
            сам.assertEqual(старые,bytes.fromhex(запись['исходное']))
            сам.assertEqual(новый,перенос.принять_пересмотр(кандидат,привязки,ВЛАДЕЛЕЦ))
            with сам.assertRaises(ValueError):перенос.применить(план,привязки,ВЛАДЕЛЕЦ)
            квитанция = перенос.применить(новый,привязки,ВЛАДЕЛЕЦ)
            сам.assertEqual(квитанция,перенос.применить(новый,привязки,ВЛАДЕЛЕЦ))
            сам.assertEqual(b'latest\x00payload',(дерево/'игнорируемый').read_bytes())
            сам.assertEqual(репо,снимок_репозиториев(дерево))
            конец = (каталог/'операция.json').read_bytes()
            with сам.assertRaises(ValueError):перенос.принять_пересмотр(кандидат,привязки,ВЛАДЕЛЕЦ)
            сам.assertEqual(конец,(каталог/'операция.json').read_bytes())

    def test_дрейф_кандидата_и_неизвестные_хвосты_не_принимаются(сам):
        for случай in ('данные','индекс','конфигурация','курсор','владелец','подготовка.tmp','готовые-байты','пересмотр-намерение.tmp','пересмотр-состояние.tmp'):
            with сам.subTest(случай=случай),tempfile.TemporaryDirectory() as временный:
                основание = Path(временный).resolve(); привязки,план,_ = прервать(основание)
                каталог = Path(привязки['состояние']); дерево=Path(привязки['назначение'])
                кандидат = перенос.пересмотреть(план,привязки,ВЛАДЕЛЕЦ)
                if случай=='данные':(дерево/'игнорируемый').write_bytes(b'new drift')
                if случай=='индекс':
                    путь = Path(привязки['общий'])/план['репозитории'][0]['каталог_метаданных']/'index'
                    путь.write_bytes(путь.read_bytes()+b'drift')
                if случай=='конфигурация':
                    путь=Path(привязки['общий'])/'config';путь.write_bytes(путь.read_bytes()+b'\n# drift\n')
                if случай=='курсор':
                    состояние=перенос.прочитать_конверт(каталог/'операция.json');состояние['номер_ремонта']+=1
                    перенос.записать_состояние(каталог/'операция.json',состояние)
                if случай.endswith('.tmp') or случай=='готовые-байты':(каталог/случай).write_bytes(b'partial')
                до=снимок_всего(основание)
                with сам.assertRaises((ValueError,OSError)):
                    перенос.принять_пересмотр(кандидат,привязки,'00000000-0000-4000-8000-000000000999' if случай=='владелец' else ВЛАДЕЛЕЦ)
                сам.assertEqual(до,снимок_всего(основание))

    def test_аварии_перехода_возобновляются_без_отката_курсора(сам):
        for точка in ('пересмотр-после-намерения','пересмотр-после-замены'):
            with сам.subTest(точка=точка),tempfile.TemporaryDirectory() as временный:
                основание=Path(временный).resolve();привязки,план,_=прервать(основание)
                кандидат=перенос.пересмотреть(план,привязки,ВЛАДЕЛЕЦ)
                путь=основание/'кандидат.json';путь.write_bytes(перенос.канон.кодировать(кандидат))
                первый=принять_процессом(путь,основание/'привязки.json',точка)
                сам.assertEqual(77,первый.returncode,первый.stderr.decode())
                повтор=принять_процессом(путь,основание/'привязки.json')
                сам.assertEqual(0,повтор.returncode,повтор.stderr.decode())
                сам.assertEqual(повтор.stdout,принять_процессом(путь,основание/'привязки.json').stdout)
                новый=перенос.канон.прочитать(повтор.stdout)
                сам.assertEqual('завершён',перенос.применить(новый,привязки,ВЛАДЕЛЕЦ)['состояние'])

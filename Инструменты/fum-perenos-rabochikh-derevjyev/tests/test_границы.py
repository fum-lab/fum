    def test_административный_корень_на_другом_томе(сам):
        from types import SimpleNamespace
        with tempfile.TemporaryDirectory() as временный:
            основание = Path(временный).resolve()
            привязки = создать(основание)
            административный = Path(гит(Path(привязки['источник']),'rev-parse','--absolute-git-dir').decode().strip())
            до = снимок_всего(основание)
            узлы = {(путь.lstat().st_dev,путь.lstat().st_ino) for путь in [административный,*административный.rglob('*')]}
            настоящее_состояние = Path.stat
            состояние_без_ссылки = Path.lstat
            состояние_дескриптора = os.fstat
            def другой_том(итог):
                if (итог.st_dev,итог.st_ino) in узлы:
                    поля = {имя:getattr(итог,имя) for имя in dir(итог) if имя.startswith('st_')}
                    поля['st_dev'] += 1
                    return SimpleNamespace(**поля)
                return итог
            def состояние(путь,*аргументы,**параметры):
                return другой_том(настоящее_состояние(путь,*аргументы,**параметры))
            def дескриптор(номер):
                return другой_том(состояние_дескриптора(номер))
            def без_ссылки(путь):
                return другой_том(состояние_без_ссылки(путь))
            with patch.object(Path,'stat',состояние),patch.object(Path,'lstat',без_ссылки),patch.object(os,'fstat',дескриптор),сам.assertRaisesRegex(ValueError,'том'):
                перенос.построить(привязки)
            сам.assertEqual(до,снимок_всего(основание))


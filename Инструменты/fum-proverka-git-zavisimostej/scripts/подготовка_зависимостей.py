class ОшибкаДопуска(RuntimeError):
    def __init__(сам, состояние, причина):
        super().__init__(причина)
        сам.состояние = состояние


class ОшибкаЧтенияГит(OSError):
    """Не попадает в исторические обработчики доказанного отказа RuntimeError."""


def хэш_файла(путь):
    путь = Path(путь)
    if путь.is_symlink() or путь.resolve() != путь.absolute():
        raise RuntimeError('символическая ссылка в служебном пути')
    if not путь.exists():
        return None
    if not путь.is_file():
        raise RuntimeError('служебный путь должен быть обычным файлом')
    return hashlib.sha256(путь.read_bytes()).hexdigest()



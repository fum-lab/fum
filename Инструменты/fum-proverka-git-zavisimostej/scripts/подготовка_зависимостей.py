def проверить_владение(корень, снимок, исполнитель, корневая_задача):
    for идентификатор in (исполнитель, корневая_задача):
        if str(uuid.UUID(идентификатор)) != идентификатор:
            raise RuntimeError('нужен точный lowercase UUID')
    if os.environ.get('CODEX_THREAD_ID') != исполнитель:
        raise RuntimeError('отсутствующий или чужой native UUID процесса')
    if снять_снимок(корень) != снимок:
        raise RuntimeError('защищённый снимок изменился')
    ссылка = снимок['ссылка']
    if not (ссылка.startswith('refs/heads/codex/') or ссылка in {'refs/heads/fuma', 'refs/heads/planirovaniye'}):
        raise RuntimeError('неподдерживаемая ветка писателя')
    текст = исходный.run_git(корень, 'worktree', 'list', '--porcelain').stdout
    владельцы = [блок.splitlines()[0].removeprefix('worktree ')
                 for блок in текст.split('\n\n') if 'branch ' + ссылка in блок.splitlines()]
    if владельцы != [str(корень)]:
        raise RuntimeError('неоднозначный владелец дерева или ref')


def прочитать_объект(путь):
    if Path(путь).is_symlink() or not Path(путь).is_file():
        raise RuntimeError('нужен обычный JSON-файл')

    return разобрать_объект(Path(путь).read_bytes())


def разобрать_объект(байты):
    def пары(записи):
        результат = {}
        for ключ, значение in записи:
            if ключ in результат:
                raise RuntimeError('повтор JSON-ключа')
            результат[ключ] = значение
        return результат

    def отказать_константе(значение):
        raise RuntimeError('недопустимая JSON-константа: ' + значение)

    return json.loads(байты.decode('utf-8'), object_pairs_hook=пары,
                      parse_constant=отказать_константе)


КАТАЛОГ_АРХИВА = 'fum-подготовка-зависимостей-архив-v1'


def прочитать_квитанцию(путь):
    путь = Path(путь)
    if путь.resolve() != путь or путь.is_symlink() or not путь.is_file():
        raise RuntimeError('нужен собственный обычный файл квитанции')
    свойства = путь.stat()
    if stat.S_IMODE(свойства.st_mode) != 0o600 or свойства.st_uid != os.geteuid():
        raise RuntimeError('квитанции нужны собственный владелец и режим 0600')
    байты = путь.read_bytes()
    try:
        данные = разобрать_объект(байты)
    except (UnicodeError, ValueError) as ошибка:
        raise RuntimeError('повреждённые JSON-байты квитанции') from ошибка
    return данные, байты


def проверить_хэш(значение):
    return type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение) is not None


def исторические_гитлинки(снимок):
    """Исторический индекс читается как данные; старый код не исполняется."""
    поля = {'схема', 'корень', 'гит_каталог', 'общий_гит_каталог', 'коммит', 'ссылка',
            'индекс', 'инвентарь_индекса', 'описание_подмодулей', 'конфигурация',
            'конфигурация_дерева', 'код'}
    if (type(снимок) is not dict or set(снимок) != поля
            or снимок['схема'] != 'fum.снимок-окружения-зависимостей.1'
            or type(снимок['коммит']) is not str
            or re.fullmatch('[0-9a-f]{40}|[0-9a-f]{64}', снимок['коммит']) is None
            or type(снимок['ссылка']) is not str
            or not (снимок['ссылка'].startswith('refs/heads/codex/')
                    or снимок['ссылка'] in {'refs/heads/fuma', 'refs/heads/planirovaniye'})
            or not проверить_хэш(снимок['индекс'])
            or not проверить_хэш(снимок['конфигурация'])
            or any(снимок[поле] is not None and not проверить_хэш(снимок[поле])
                   for поле in ('описание_подмодулей', 'конфигурация_дерева'))
            or type(снимок['код']) is not dict or set(снимок['код']) != set(ОТПЕЧАТОК_КОДА)
            or any(not проверить_хэш(значение) for значение in снимок['код'].values())):
        raise RuntimeError('повреждённая форма исторического снимка')
    for поле in ('корень', 'гит_каталог', 'общий_гит_каталог'):
        значение = снимок[поле]
        if type(значение) is not str or not Path(значение).is_absolute() or str(Path(значение)) != значение:
            raise RuntimeError('неканонический путь исторического снимка')
    текст = снимок['инвентарь_индекса']
    if type(текст) is not str or (текст and not текст.endswith('\0')):
        raise RuntimeError('неполный исторический NUL-инвентарь')
    записи, зависимости = set(), {}
    for строка in текст.split('\0')[:-1] if текст else []:
        метаданные, разделитель, путь = строка.partition('\t')
        совпадение = re.fullmatch(r'H (100644|100755|120000|160000) ([0-9a-f]{40}|[0-9a-f]{64}) 0', метаданные)
        if (not разделитель or совпадение is None or not путь or путь in записи
                or путь != PurePosixPath(путь).as_posix() or PurePosixPath(путь).is_absolute()
                or any(часть in {'.', '..'} for часть in PurePosixPath(путь).parts)):
            raise RuntimeError('повреждённая историческая запись stage0')
        записи.add(путь)
        if совпадение[1] == '160000':
            if исходный.validate_dependency_path(путь) or any(ord(символ) < 32 or ord(символ) == 127 for символ in путь):
                raise RuntimeError('небезопасный исторический путь зависимости')
            зависимости[путь] = совпадение[2]
    if зависимости and ('.gitmodules' not in записи or снимок['описание_подмодулей'] is None):
        raise RuntimeError('исторические gitlinks не имеют описания')
    return зависимости


def путь_архива(собственный, хэш, *, создать=False):
    if not проверить_хэш(хэш):
        raise RuntimeError('нужен lowercase SHA-256 предшественника')
    каталог = собственный / КАТАЛОГ_АРХИВА
    if создать and not os.path.lexists(каталог):
        каталог.mkdir(mode=0o700)
        синхронизировать_каталог(собственный)
    if (каталог.resolve() != каталог or каталог.is_symlink() or not каталог.is_dir()
            or stat.S_IMODE(каталог.stat().st_mode) != 0o700 or каталог.stat().st_uid != os.geteuid()):
        raise RuntimeError('небезопасный собственный каталог архива')
    return каталог / (хэш + '.json')


def синхронизировать_каталог(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def проверить_цепочку(данные, собственный, исполнитель, корневая_задача):
    """Итеративно проверяет каждое звено до v1, включая наследуемый запрет init."""
    if type(данные) is not dict or type(данные.get('снимок')) is not dict:
        raise RuntimeError('повреждённая форма активной квитанции')
    исторические_гитлинки(данные['снимок'])
    исходная_топология = {поле: данные['снимок'][поле]
                         for поле in ('корень', 'гит_каталог', 'общий_гит_каталог', 'ссылка')}
    просмотренные, наследуемые = set(), set()
    текущие = данные
    while True:
        ревизии = исторические_гитлинки(текущие['снимок'])
        проверить_квитанцию(текущие, текущие['снимок'], исполнитель, корневая_задача, set(ревизии))
        if {поле: текущие['снимок'][поле] for поле in исходная_топология} != исходная_топология:
            raise RuntimeError('топология цепочки изменилась')
        if текущие['схема'] == 'fum.подготовка-зависимостей.1':
            return наследуемые
        хэш = текущие['предыдущая_квитанция']['sha256']
        if хэш in просмотренные:
            raise RuntimeError('повтор SHA или цикл в цепочке')
        просмотренные.add(хэш)
        прежние, байты = прочитать_квитанцию(путь_архива(собственный, хэш))
        if hashlib.sha256(байты).hexdigest() != хэш:
            raise RuntimeError('архив не совпадает с SHA предшественника')
        if type(прежние) is not dict or type(прежние.get('снимок')) is not dict:
            raise RuntimeError('повреждённый предшественник')
        старые_ревизии = исторические_гитлинки(прежние['снимок'])
        проверить_квитанцию(прежние, прежние['снимок'], исполнитель, корневая_задача, set(старые_ревизии))
        if not прежние['готова'] or any(состояние != 'готова' for состояние in прежние['состояния'].values()):
            raise RuntimeError('предшественник не финализирован')
        for путь, ревизия in старые_ревизии.items():
            if (ревизии.get(путь) != ревизия or текущие['состояния'].get(путь) != 'готова'
                    or any(событие['путь'] == путь and событие['фаза'] != 'автономное_подтверждение'
                           for событие in текущие['события'])):
                raise RuntimeError('прежний готовый путь или его запрет init утрачен')
        наследуемые.update(старые_ревизии)
        текущие = прежние


def сохранить_архив(собственный, хэш, байты):
    путь = путь_архива(собственный, хэш, создать=True)
    try:
        дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    except FileExistsError:
        _, прежние_байты = прочитать_квитанцию(путь)
        if прежние_байты != байты:
            raise RuntimeError('архив занят другими байтами')
        дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
        try:
            os.fsync(дескриптор)
        finally:
            os.close(дескриптор)
    else:
        with os.fdopen(дескриптор, 'wb') as файл:
            файл.write(байты); файл.flush(); os.fsync(файл.fileno())
    синхронизировать_каталог(путь.parent)
    return путь


def записать_квитанцию(путь, данные):
    проверить_квитанцию(данные, данные['снимок'], данные['исполнитель'],
                       данные['корневая_задача'], set(данные['состояния']))
    проверить_цепочку(данные, путь.parent, данные['исполнитель'], данные['корневая_задача'])
    временный = путь.with_name(путь.name + '.' + str(uuid.uuid4()) + '.tmp')
    дескриптор = os.open(временный, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(дескриптор, 'w', encoding='utf-8') as файл:
        json.dump(данные, файл, ensure_ascii=False, sort_keys=True, indent=2)
        файл.write('\n'); файл.flush(); os.fsync(файл.fileno())
    os.replace(временный, путь)
    дескриптор = os.open(путь.parent, os.O_RDONLY)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def группа_жива(номер):
    if type(номер) is not int or номер <= 0:
        raise RuntimeError('неизвестная прежняя группа процессов')
    try:
        os.killpg(номер, 0)
        return True
    except ProcessLookupError:
        return False
    except PermissionError:
        return True


СОСТОЯНИЯ_ПОПЫТКИ = {'не_начата', 'выполняется', 'не_завершена', 'готова'}
ФАЗЫ_ЭФФЕКТОВ = ('материализация', 'добавление_источника_оригинала',
                 'получение_форка', 'получение_оригинала', 'выбор_ревизии')


def проверить_квитанцию(данные, снимок, исполнитель, корневая_задача, пути):
    поля = {'схема', 'снимок', 'исполнитель', 'корневая_задача', 'группа_процессов',
            'состояния', 'события', 'готова'}
    if type(данные) is dict and данные.get('схема') == 'fum.подготовка-зависимостей.2':
        поля |= {'предыдущая_квитанция'}
        предшественник = данные.get('предыдущая_квитанция')
        if (type(предшественник) is not dict or set(предшественник) != {'sha256'}
                or not проверить_хэш(предшественник['sha256'])):
            raise RuntimeError('повреждённая ссылка на предшественника')
    if (type(данные) is not dict or set(данные) != поля
            or данные['схема'] not in {'fum.подготовка-зависимостей.1', 'fum.подготовка-зависимостей.2'}
            or данные['снимок'] != снимок or данные['исполнитель'] != исполнитель
            or данные['корневая_задача'] != корневая_задача
            or type(данные['готова']) is not bool
            or type(данные['группа_процессов']) is not int or данные['группа_процессов'] <= 0
            or type(данные['состояния']) is not dict or set(данные['состояния']) != пути
            or any(type(состояние) is not str or состояние not in СОСТОЯНИЯ_ПОПЫТКИ
                   for состояние in данные['состояния'].values())
            or type(данные['события']) is not list):
        raise RuntimeError('чужая, повреждённая или изменившаяся квитанция')
    состояния = {путь: 'не_начата' for путь in пути}
    фазы, группы = {}, {}
    for событие in данные['события']:
        if (type(событие) is not dict or type(событие.get('путь')) is not str
                or событие['путь'] not in пути or type(событие.get('фаза')) is not str):
            raise RuntimeError('повреждённое событие квитанции')
        путь, фаза = событие['путь'], событие['фаза']
        прежнее = состояния[путь]
        if фаза == 'намерение' or фаза in ФАЗЫ_ЭФФЕКТОВ:
            if (set(событие) != {'путь', 'фаза', 'группа_процессов'}
                    or type(событие['группа_процессов']) is not int or событие['группа_процессов'] <= 0):
                raise RuntimeError('некорректная группа события')
            if фаза == 'намерение':
                if прежнее != 'не_начата':
                    raise RuntimeError('повтор или неверный порядок намерения')
                группы[путь] = событие['группа_процессов']
                фазы[путь] = -1
            else:
                номер = ФАЗЫ_ЭФФЕКТОВ.index(фаза)
                предыдущая = фазы.get(путь, -2)
                if (прежнее != 'выполняется' or событие['группа_процессов'] != группы.get(путь)
                        or not (номер == предыдущая + 1 or (предыдущая == 0 and номер == 2))):
                    raise RuntimeError('нарушена последовательность эффектов')
                фазы[путь] = номер
            состояния[путь] = 'выполняется'
        elif фаза == 'отказ':
            if (set(событие) != {'путь', 'фаза', 'причина'}
                    or type(событие['причина']) is not str or прежнее != 'выполняется'):
                raise RuntimeError('некорректный отказ в истории')
            состояния[путь] = 'не_завершена'
        elif фаза == 'готовность_проверена':
            if (set(событие) != {'путь', 'фаза'} or прежнее != 'выполняется'
                    or фазы.get(путь) != len(ФАЗЫ_ЭФФЕКТОВ) - 1):
                raise RuntimeError('готовность записана без завершения эффекта')
            состояния[путь] = 'готова'
        elif фаза == 'автономное_подтверждение':
            if (set(событие) != {'путь', 'фаза', 'прежнее_состояние', 'прежний_исход_неизвестен'}
                    or событие['прежнее_состояние'] != прежнее
                    or type(событие['прежний_исход_неизвестен']) is not bool
                    or событие['прежний_исход_неизвестен'] != (прежнее in {'выполняется', 'не_завершена'})):
                raise RuntimeError('некорректное автономное подтверждение')
            состояния[путь] = 'готова'
        else:
            raise RuntimeError('неизвестная фаза квитанции')
    if состояния != данные['состояния'] or (данные['готова'] and any(с != 'готова' for с in состояния.values())):
        raise RuntimeError('история и итог квитанции расходятся')


def начать_новую_попытку(корень_репозитория, снимок, исполнитель, корневая_задача,
                         *, ожидаемый_хэш_квитанции):
    корень = нормализовать_корень(корень_репозитория)
    проверить_владение(корень, снимок, исполнитель, корневая_задача)
    if not проверить_хэш(ожидаемый_хэш_квитанции):
        raise RuntimeError('нужен независимо закреплённый SHA-256 старой квитанции')
    собственный = Path(снимок['гит_каталог'])
    if собственный.resolve() != собственный or not собственный.is_dir():
        raise RuntimeError('небезопасный собственный Git-каталог')
    квитанция = собственный / 'fum-подготовка-зависимостей-v1.json'
    замок = квитанция.with_suffix('.lock')
    инвентарь = прочитать_инвентарь(корень)

    def допуск():
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        данные, байты = прочитать_квитанцию(квитанция)
        if hashlib.sha256(байты).hexdigest() != ожидаемый_хэш_квитанции:
            raise RuntimeError('активная квитанция не совпадает с ожидаемым SHA-256')
        if type(данные) is not dict or type(данные.get('снимок')) is not dict:
            raise RuntimeError('повреждённая активная квитанция')
        проверить_цепочку(данные, собственный, исполнитель, корневая_задача)
        if not данные['готова'] or any(состояние != 'готова' for состояние in данные['состояния'].values()):
            raise RuntimeError('прежняя попытка не финализирована')
        if группа_жива(данные['группа_процессов']):
            raise RuntimeError('прежняя группа ещё жива')
        for поле in ('корень', 'гит_каталог', 'общий_гит_каталог', 'ссылка'):
            if данные['снимок'][поле] != снимок[поле]:
                raise RuntimeError('переход не сохраняет идентичность и топологию')
        старые_ревизии = исторические_гитлинки(данные['снимок'])
        текущие_ревизии = исторические_гитлинки(снимок)
        if any(текущие_ревизии.get(путь) != ревизия for путь, ревизия in старые_ревизии.items()):
            raise RuntimeError('прежний путь исчез или его gitlink изменился')
        результаты = [проверить_запись(корень, запись) for запись in инвентарь]
        if any(результат['состояние'] not in {'готова', 'не_материализована'}
               or (результат['путь'] in старые_ревизии and not результат['готова'])
               for результат in результаты):
            raise RuntimeError('инвентарь не допускает перехода; прежняя готовность утрачена')
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        return данные, байты, результаты

    _, прежние_байты, _ = допуск()
    if замок.is_symlink() or (замок.exists() and not замок.is_file()):
        raise RuntimeError('небезопасный путь блокировки')
    дескриптор = os.open(замок, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    try:
        try:
            fcntl.flock(дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as ошибка:
            raise RuntimeError('подготовка уже выполняется') from ошибка
        _, байты, результаты = допуск()
        if байты != прежние_байты:
            raise RuntimeError('квитанция конкурентно изменилась')
        архив = сохранить_архив(собственный, ожидаемый_хэш_квитанции, байты)
        _, проверенные_байты, результаты = допуск()
        if проверенные_байты != байты:
            raise RuntimeError('квитанция изменилась перед установкой')
        данные = {'схема': 'fum.подготовка-зависимостей.2', 'снимок': снимок,
                  'исполнитель': исполнитель, 'корневая_задача': корневая_задача,
                  'группа_процессов': os.getpgrp(), 'состояния': {}, 'события': [],
                  'готова': False, 'предыдущая_квитанция': {'sha256': ожидаемый_хэш_квитанции}}
        for результат in результаты:
            путь = результат['путь']
            данные['состояния'][путь] = 'готова' if результат['готова'] else 'не_начата'
            if результат['готова']:
                данные['события'].append({'путь': путь, 'фаза': 'автономное_подтверждение',
                    'прежнее_состояние': 'не_начата', 'прежний_исход_неизвестен': False})
        записать_квитанцию(квитанция, данные)
        return {'схема': 'fum.результат-новой-попытки-зависимостей.1', 'попытка_создана': True,
                'квитанция': str(квитанция), 'архив': str(архив), 'предыдущая_квитанция': {'sha256': ожидаемый_хэш_квитанции}}
    finally:
        os.close(дескриптор)


def подготовить_зависимости(корень_репозитория, снимок, исполнитель, корневая_задача,
                            *, возобновить=False):
    корень = нормализовать_корень(корень_репозитория)
    проверить_владение(корень, снимок, исполнитель, корневая_задача)
    инвентарь = прочитать_инвентарь(корень)
    результаты = [проверить_запись(корень, запись) for запись in инвентарь]
    if any(результат['состояние'] not in {'готова', 'не_материализована'} for результат in результаты):
        raise RuntimeError('инвентарь содержит неподготовимое состояние: ' +
                           ', '.join(результат['состояние'] for результат in результаты if not результат['готова']))
    собственный = Path(снимок['гит_каталог'])
    if собственный.resolve() != собственный or not собственный.is_dir():
        raise RuntimeError('небезопасный собственный Git-каталог')
    квитанция = собственный / 'fum-подготовка-зависимостей-v1.json'
    замок = собственный / 'fum-подготовка-зависимостей-v1.lock'
    прежняя = None
    прежние_байты = None
    if квитанция.exists() or квитанция.is_symlink():
        прежняя, прежние_байты = прочитать_квитанцию(квитанция)
        проверить_квитанцию(прежняя, снимок, исполнитель, корневая_задача,
                           {запись['путь'] for запись in инвентарь})
        проверить_цепочку(прежняя, собственный, исполнитель, корневая_задача)
        if any(прежняя['состояния'][результат['путь']] == 'готова' and not результат['готова']
               for результат in результаты):
            raise RuntimeError('прежде готовая копия изменилась; новая инициализация запрещена')
        незавершённые = {путь for путь, состояние in прежняя['состояния'].items()
                        if состояние in {'выполняется', 'не_завершена'}}
        if незавершённые:
            if not возобновить or группа_жива(прежняя['группа_процессов']):
                raise RuntimeError('незавершённая попытка: нужен явный допуск после остановки её группы')
            if any(not результат['готова'] for результат in результаты if результат['путь'] in незавершённые):
                raise RuntimeError('исход неизвестен; готовность не подтверждена; повтор init запрещён')
        elif возобновить:
            raise RuntimeError('нет незавершённой попытки для возобновления')
    elif возобновить:
        raise RuntimeError('квитанция для возобновления отсутствует')
    if os.getpid() != os.getpgrp():
        raise RuntimeError('подготовке нужна собственная группа процессов; используйте CLI')
    if замок.is_symlink() or (замок.exists() and not замок.is_file()):
        raise RuntimeError('небезопасный путь блокировки')
    дескриптор = os.open(замок, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    try:
        try:
            fcntl.flock(дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as ошибка:
            raise RuntimeError('подготовка уже выполняется') from ошибка
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        if (прочитать_квитанцию(квитанция)[1] if os.path.lexists(квитанция) else None) != прежние_байты:
            raise RuntimeError('квитанция конкурентно изменилась')
        if прежняя is not None:
            проверить_квитанцию(прежняя, снимок, исполнитель, корневая_задача,
                               {запись['путь'] for запись in инвентарь})
            проверить_цепочку(прежняя, собственный, исполнитель, корневая_задача)
        if прежняя is not None and прежняя['готова']:
            итог = проверить_зависимости(корень)
            проверить_владение(корень, снимок, исполнитель, корневая_задача)
            if not итог['готова']:
                raise RuntimeError('готовый повтор утратил готовность')
            return {'схема': 'fum.результат-подготовки-зависимостей.1', 'готова': True,
                    'квитанция': str(квитанция), 'зависимости': итог['зависимости'],
                    'без_повторных_эффектов': True}
        данные = прежняя or {'схема': 'fum.подготовка-зависимостей.1', 'снимок': снимок,
                    'исполнитель': исполнитель, 'корневая_задача': корневая_задача,
                    'группа_процессов': os.getpgrp(), 'состояния': {запись['путь']: 'не_начата' for запись in инвентарь},
                    'события': [], 'готова': False}
        данные['группа_процессов'] = os.getpgrp()
        for запись in инвентарь:
            путь = запись['путь']
            готовность = проверить_запись(корень, запись)
            if готовность['готова']:
                прежнее_состояние = данные['состояния'][путь]
                данные['состояния'][путь] = 'готова'
                данные['события'].append({'путь': путь, 'фаза': 'автономное_подтверждение',
                    'прежнее_состояние': прежнее_состояние, 'прежний_исход_неизвестен': прежнее_состояние in {'выполняется', 'не_завершена'}})
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
                записать_квитанцию(квитанция, данные)
                continue
            if готовность['состояние'] != 'не_материализована' or данные['состояния'][путь] != 'не_начата':
                raise RuntimeError('попытка не допускает нового init')

            def перед_эффектом(фаза):
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
                проверить_цепочку(данные, собственный, исполнитель, корневая_задача)
                for защищённая in инвентарь:
                    if (данные['состояния'][защищённая['путь']] == 'готова'
                            and not проверить_запись(корень, защищённая)['готова']):
                        raise RuntimeError('прежде готовая копия изменилась перед эффектом; init запрещён')
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
                данные['состояния'][путь] = 'выполняется'
                данные['события'].append({'путь': путь, 'фаза': фаза, 'группа_процессов': os.getpgrp()})
                записать_квитанцию(квитанция, данные)

            перед_эффектом('намерение')
            try:
                _, ошибки = исходный.initialize_registered_dependency(корень, путь, перед_эффектом=перед_эффектом)
                готовность = проверить_запись(корень, запись)
                if ошибки or not готовность['готова']:
                    raise RuntimeError('; '.join(ошибки) or готовность['состояние'])
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
            except BaseException as ошибка:
                данные['состояния'][путь] = 'не_завершена'
                данные['события'].append({'путь': путь, 'фаза': 'отказ', 'причина': str(ошибка)})
                записать_квитанцию(квитанция, данные)
                raise
            данные['состояния'][путь] = 'готова'
            данные['события'].append({'путь': путь, 'фаза': 'готовность_проверена'})
            записать_квитанцию(квитанция, данные)
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        итог = проверить_зависимости(корень)
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        if not итог['готова']:
            raise RuntimeError('итоговая готовность не подтверждена')
        данные['готова'] = True
        записать_квитанцию(квитанция, данные)
        return {'схема': 'fum.результат-подготовки-зависимостей.1', 'готова': True,
                'квитанция': str(квитанция), 'зависимости': итог['зависимости'], 'без_повторных_эффектов': False}
    finally:
        os.close(дескриптор)


def выполнить_команду():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('команда', choices=['готовность', 'проверить', 'снимок', 'подготовить', 'возобновить', 'новая-попытка'])
    разбор.add_argument('--корень-репозитория', required=True)
    разбор.add_argument('--путь')
    разбор.add_argument('--ожидаемая-ревизия')
    разбор.add_argument('--снимок')
    разбор.add_argument('--исполнитель')
    разбор.add_argument('--корневая-задача')
    разбор.add_argument('--ожидаемый-хэш-квитанции')
    параметры = разбор.parse_args()
    try:
        if параметры.команда == 'готовность':
            if not параметры.путь:
                raise RuntimeError('готовность требует --путь')
            результат = проверить_готовность_зависимости(параметры.корень_репозитория, параметры.путь,
                                                        ожидаемая_ревизия=параметры.ожидаемая_ревизия)
        elif параметры.команда == 'проверить':
            результат = проверить_зависимости(параметры.корень_репозитория)
        elif параметры.команда == 'снимок':
            результат = снять_снимок(параметры.корень_репозитория)
        else:
            if not all((параметры.снимок, параметры.исполнитель, параметры.корневая_задача)):
                raise RuntimeError('подготовка требует снимок и оба UUID')
            if os.getpid() != os.getpgrp():
                os.setsid()
            if параметры.команда == 'новая-попытка':
                результат = начать_новую_попытку(параметры.корень_репозитория, прочитать_объект(параметры.снимок),
                    параметры.исполнитель, параметры.корневая_задача,
                    ожидаемый_хэш_квитанции=параметры.ожидаемый_хэш_квитанции)
            else:
                результат = подготовить_зависимости(параметры.корень_репозитория, прочитать_объект(параметры.снимок),
                    параметры.исполнитель, параметры.корневая_задача, возобновить=параметры.команда == 'возобновить')
        print(json.dumps(результат, ensure_ascii=False, sort_keys=True))
        if результат.get('состояние') == 'неизвестность':
            return 2
        return 0 if результат.get('готова', True) else 1
    except ОшибкаДопуска as ошибка:
        print(json.dumps({'схема': 'fum.отказ-подготовки-зависимостей.1', 'готова': False,
                          'состояние': ошибка.состояние, 'причина': str(ошибка)}, ensure_ascii=False))
        return 1
    except (OSError, UnicodeError, RuntimeError, ValueError) as ошибка:
        print(json.dumps({'схема': 'fum.отказ-подготовки-зависимостей.1', 'готова': False,
                          'причина': str(ошибка)}, ensure_ascii=False))
        return 2


if __name__ == '__main__':
    raise SystemExit(выполнить_команду())

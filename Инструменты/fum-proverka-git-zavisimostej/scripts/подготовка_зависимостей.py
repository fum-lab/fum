def проверить_полноту(корень):
    результат = исходный.run_git(корень, 'config', '--get-regexp',
        r'^(extensions\.partialclone|remote\..*\.(promisor|partialclonefilter))$',
        allowed_returncodes=(0, 1))
    if результат.returncode == 0:
        raise ОшибкаДопуска('неполная_копия', 'partial/promisor-копия не поддерживается')
    if исходный.run_git(корень, 'rev-parse', '--is-shallow-repository').stdout != 'false':
        raise ОшибкаДопуска('неполная_копия', 'shallow-копия не поддерживается')


def нормализовать_корень(корень):
    путь = Path(корень).absolute()
    if путь.resolve() != путь:
        raise RuntimeError('корень не должен проходить через символические ссылки')
    ошибки = исходный.validate_repo_root(путь)
    if ошибки:
        raise ОшибкаДопуска('неверная_топология', '; '.join(ошибки))
    проверить_полноту(путь)
    return путь


def индексные_записи(корень):
    текст = исходный.run_git(корень, 'ls-files', '--stage', '-z', strip_output=False).stdout
    if текст and not текст.endswith('\0'):
        raise ОшибкаДопуска('нарушен_индекс', 'некорректный NUL-инвентарь индекса')
    записи = {}
    for строка in текст.split('\0'):
        if not строка:
            continue
        метаданные, разделитель, путь = строка.partition('\t')
        поля = метаданные.split()
        if not разделитель or len(поля) != 3 or поля[2] != '0' or путь in записи:
            raise ОшибкаДопуска('нарушен_индекс', 'конфликтующий или некорректный индекс')
        записи[путь] = {'режим': поля[0], 'ревизия': поля[1]}
    return записи


def прочитать_инвентарь(корень):
    корень = нормализовать_корень(корень)
    ошибки = исходный.проверить_флаги_индекса(корень, 'суперпроект')
    if ошибки:
        raise ОшибкаДопуска('скрывающие_флаги', '; '.join(ошибки))
    записи = индексные_записи(корень)
    пути = {путь for путь, запись in записи.items() if запись['режим'] == '160000'}
    файл = корень / '.gitmodules'
    if '.gitmodules' not in записи and not файл.exists() and not файл.is_symlink():
        if пути:
            raise ОшибкаДопуска('нарушена_регистрация', 'gitlinks не имеют .gitmodules')
        return []
    if файл.is_symlink() or not файл.is_file() or записи.get('.gitmodules', {}).get('режим') != '100644':
        raise ОшибкаДопуска('нарушена_регистрация', '.gitmodules должна быть обычным индексированным файлом')
    файл.read_text(encoding='utf-8')
    ревизия = исходный.run_git(корень, 'hash-object', '--no-filters', '--', '.gitmodules').stdout
    if ревизия != записи['.gitmodules']['ревизия']:
        raise ОшибкаДопуска('нарушена_регистрация', '.gitmodules не совпадает с точным blob индекса')
    результат = исходный.run_git(корень, 'config', '--no-includes', '-z', '-f', '.gitmodules',
                                 '--list', strip_output=False)
    разделы = {}
    for строка in результат.stdout.split('\0'):
        if not строка:
            continue
        ключ, разделитель, значение = строка.partition('\n')
        раздел, точка, поле = ключ.rpartition('.')
        if not разделитель or not точка or not раздел.startswith('submodule.'):
            raise ОшибкаДопуска('нарушена_регистрация', 'посторонняя или некорректная запись .gitmodules')
        разделы.setdefault(раздел, {}).setdefault(поле, []).append(значение)
    регистрации = {}
    for раздел, поля in разделы.items():
        for поле in ('path', 'url', 'fumupstream'):
            значения = поля.get(поле, [])
            if len(значения) != 1 or not значения[0].strip():
                raise ОшибкаДопуска('нарушена_регистрация', 'каждой секции нужны единственные path/url/fumUpstream')
        путь = поля['path'][0]
        if путь in регистрации:
            raise ОшибкаДопуска('нарушена_регистрация', 'неоднозначный инвентарь .gitmodules')
        регистрации[путь] = раздел
    if set(регистрации) != пути:
        raise ОшибкаДопуска('нарушена_регистрация', 'инвентарь .gitmodules не совпадает со stage0 gitlinks')
    инвентарь = []
    for путь in sorted(пути):
        if (исходный.validate_dependency_path(путь) or путь != PurePosixPath(путь).as_posix()
                or any(ord(символ) < 32 or ord(символ) == 127 for символ in путь)):
            raise ОшибкаДопуска('небезопасный_путь', 'небезопасный путь в инвентаре')
        описание, ошибки = исходный.registered_dependency_spec(корень, путь)
        if описание is None or ошибки:
            raise ОшибкаДопуска('нарушена_регистрация', '; '.join(ошибки) or 'нарушена регистрация')
        каталог, ошибки = исходный.expected_submodule_git_directory(корень, путь, регистрации[путь])
        if каталог is None or ошибки:
            raise ОшибкаДопуска('небезопасный_путь', '; '.join(ошибки) or 'неизвестный Git-каталог')
        инвентарь.append({'путь': путь, 'раздел': регистрации[путь], 'описание': описание,
                          'каталог': каталог})
    for номер, запись in enumerate(инвентарь):
        for другая in инвентарь[номер + 1:]:
            for левый, правый in ((запись['путь'], другая['путь']),
                                  (str(запись['каталог']), str(другая['каталог']))):
                левый, правый = левый.casefold(), правый.casefold()
                if левый == правый or левый.startswith(правый + '/') or правый.startswith(левый + '/'):
                    raise ОшибкаДопуска('небезопасный_путь', 'пути зависимостей или Git-каталогов пересекаются')
    return инвентарь


def диагноз(путь, состояние, *, ревизия=None, ожидаемая=None, фактическая=None,
            корень_копии='неизвестно', причины=()):
    return {'схема': 'fum.готовность-зависимости.1', 'путь': путь,
            'готова': состояние == 'готова', 'состояние': состояние,
            'ревизия_индекса': ревизия, 'ожидаемая_ревизия': ожидаемая,
            'фактическая_ревизия': фактическая, 'корень_копии': корень_копии,
            'причины': [{'вид': состояние, 'проверка': причина} for причина in причины]}


def проверить_форму_графа(граф, описание):
    поля = {'схема', 'родитель', 'дерево', 'описание_подмодулей', 'гитлинки', 'листья', 'нематериализованные'}
    родитель = {'адрес_форка': описание.fork_url, 'адрес_оригинала': описание.upstream_url,
                'путь': описание.path, 'ревизия': описание.revision}
    if (type(граф) is not dict or set(граф) != поля or граф['схема'] != 'fum.граф-зависимости.1'
            or граф['родитель'] != родитель):
        raise RuntimeError('граф не связан с точным выбранным родителем')
    длина = len(описание.revision)
    def объект(значение):
        return type(значение) is str and re.fullmatch('[0-9a-f]{' + str(длина) + '}', значение) is not None
    if (not объект(граф['дерево']) or type(граф['описание_подмодулей']) is not str
            or re.fullmatch('[0-9a-f]{64}', граф['описание_подмодулей']) is None
            or type(граф['гитлинки']) is not dict or not граф['гитлинки']
            or type(граф['листья']) is not list or not граф['листья']
            or type(граф['нематериализованные']) is not list):
        raise RuntimeError('неверная закрытая форма конечного графа')
    пути = list(граф['гитлинки'])
    for путь in пути:
        if (type(путь) is not str or исходный.validate_dependency_path(путь) or путь != PurePosixPath(путь).as_posix()
                or any(ord(буква) < 32 or ord(буква) == 127 for буква in путь)
                or not объект(граф['гитлинки'][путь])):
            raise RuntimeError('небезопасный путь или OID графа')
    for номер, путь in enumerate(пути):
        for другой in пути[номер + 1:]:
            левый, правый = (unicodedata.normalize('NFC', значение).casefold() for значение in (путь, другой))
            if левый == правый or левый.startswith(правый + '/') or правый.startswith(левый + '/'):
                raise RuntimeError('пересекающиеся пути графа')
    выбранные = []
    for лист in граф['листья']:
        if (type(лист) is not dict or set(лист) != {'путь', 'ревизия', 'адрес_форка', 'адрес_оригинала',
                                                   'дерево', 'первичные_ответы'}
                or type(лист['путь']) is not str or лист['путь'] not in граф['гитлинки']
                or any(type(лист[поле]) is not str for поле in ('адрес_форка', 'адрес_оригинала', 'ревизия'))
                or лист['ревизия'] != граф['гитлинки'][лист['путь']] or not объект(лист['дерево'])):
            raise RuntimeError('лист не совпадает с выбранным gitlink')
        описание_листа = исходный.DependencySpec(лист['адрес_форка'], лист['адрес_оригинала'],
                                                лист['путь'], лист['ревизия'])
        исходный.проверить_первичное_родство(описание_листа, лист['первичные_ответы'], разобрать_объект)
        ошибки = исходный.validate_spec(описание_листа)
        for роль, адрес in (('origin листа', лист['адрес_форка']), ('upstream листа', лист['адрес_оригинала'])):
            ошибки += исходный.validate_public_github_https_url(адрес, роль)
        форк, _ = исходный.parse_repository_location(лист['адрес_форка'])
        родитель_форк, _ = исходный.parse_repository_location(описание.fork_url)
        if ошибки or форк is None or родитель_форк is None or форк.namespace.casefold() != родитель_форк.namespace.casefold():
            raise RuntimeError('; '.join(ошибки) or 'зеркало листа принадлежит другому владельцу')
        выбранные.append(лист['путь'])
    остальные = граф['нематериализованные']
    if (any(type(путь) is not str for путь in остальные) or len(set(остальные)) != len(остальные)
            or len(set(выбранные)) != len(выбранные) or set(выбранные) & set(остальные)
            or set(выбранные) | set(остальные) != set(пути)):
        raise RuntimeError('полный состав графа не разделён однозначно')


def прочитать_дерево_гит(корень, ревизия):
    текст = исходный.run_git(корень, 'ls-tree', '-r', '-z', ревизия, strip_output=False).stdout
    if текст and not текст.endswith('\0'):
        raise RuntimeError('неполный NUL-инвентарь дерева')
    записи = {}
    for строка in текст.split('\0')[:-1]:
        метаданные, путь = строка.split('\t', 1)
        режим, вид, объект = метаданные.split()
        if путь in записи:
            raise RuntimeError('неоднозначный путь дерева')
        записи[путь] = (режим, вид, объект)
    return записи


def проверить_дерево_графа(корень, ревизия, граф=None):
    записи = прочитать_дерево_гит(корень, ревизия)
    вложенные = {путь: данные[2] for путь, данные in записи.items() if данные[0] == '160000'}
    if граф is None:
        if вложенные:
            raise RuntimeError('вложенный граф требует явного конечного допуска')
        return {}
    if (ревизия != граф['родитель']['ревизия']
            or исходный.run_git(корень, 'rev-parse', ревизия + '^{tree}').stdout != граф['дерево']
            or вложенные != граф['гитлинки'] or записи.get('.gitmodules', ('',))[0] != '100644'):
        raise RuntimeError('родительское дерево, pin или полный состав gitlinks не совпадают')
    байты = исходный.run_git(корень, 'cat-file', 'blob', записи['.gitmodules'][2], strip_output=False, сырые_байты=True).stdout
    if hashlib.sha256(байты).hexdigest() != граф['описание_подмодулей']:
        raise RuntimeError('первичные байты .gitmodules родителя отличаются')
    текст = исходный.run_git(корень, 'config', '--no-includes', '-z', '--blob',
                             ревизия + ':.gitmodules', '--list', strip_output=False).stdout
    разделы = {}
    for строка in текст.split('\0')[:-1]:
        ключ, значение = строка.split('\n', 1)
        раздел, _, поле = ключ.rpartition('.')
        if not раздел.startswith('submodule.'):
            raise RuntimeError('посторонняя секция первичной .gitmodules')
        разделы.setdefault(раздел, {}).setdefault(поле, []).append(значение)
    привязки = {}
    имена = []
    for раздел, поля in разделы.items():
        if len(поля.get('path', [])) != 1 or len(поля.get('url', [])) != 1:
            raise RuntimeError('неоднозначная первичная секция подмодуля')
        путь = поля['path'][0]
        имя = раздел.removeprefix('submodule.')
        if (исходный.validate_dependency_path(имя) or имя != PurePosixPath(имя).as_posix()
                or any(ord(буква) < 32 or ord(буква) == 127 for буква in имя)):
            raise RuntimeError('небезопасное имя первичной секции подмодуля')
        свёрнутое = unicodedata.normalize('NFC', имя).casefold()
        if any(свёрнутое == другое or свёрнутое.startswith(другое + '/') or другое.startswith(свёрнутое + '/') for другое in имена):
            raise RuntimeError('имена первичных секций пересекаются')
        имена.append(свёрнутое)
        if путь in привязки or путь not in вложенные:
            raise RuntimeError('секции первичной .gitmodules не совпадают с полным графом')
        привязки[путь] = (раздел, поля['url'][0])
    if set(привязки) != set(вложенные):
        raise RuntimeError('неполный первичный инвентарь секций')
    for лист in граф['листья']:
        if привязки[лист['путь']][1] != лист['адрес_оригинала']:
            raise RuntimeError('первичный URL листа не совпадает с выбранным upstream')
    return привязки


def проверить_родителя_графа(родитель, граф):
    описание = исходный.DependencySpec(*(граф['родитель'][ключ]
        for ключ in ('адрес_форка', 'адрес_оригинала', 'путь', 'ревизия')))
    проверить_форму_графа(граф, описание)
    привязки = проверить_дерево_графа(родитель, описание.revision, граф)
    проверить_полноту(родитель)
    if (исходный.run_git(родитель, 'rev-parse', 'HEAD').stdout != описание.revision
            or исходный.run_git(родитель, 'symbolic-ref', '-q', 'HEAD', allowed_returncodes=(0, 1)).returncode != 1
            or исходный.проверить_флаги_индекса(родитель, описание.path)):
        raise RuntimeError('HEAD или флаги индекса родителя изменены')
    if индексные_записи(родитель) != {путь: {'режим': данные[0], 'ревизия': данные[2]}
            for путь, данные in прочитать_дерево_гит(родитель, описание.revision).items()}:
        raise RuntimeError('индекс родителя не совпадает с первичным деревом')
    файл = родитель / '.gitmodules'
    if файл.is_symlink() or not файл.is_file() or hashlib.sha256(файл.read_bytes()).hexdigest() != граф['описание_подмодулей']:
        raise RuntimeError('первичная .gitmodules родителя изменена')
    if исходный.run_git(родитель, 'status', '--porcelain=v1', '--ignore-submodules=all', '--untracked-files=all', '--ignored').stdout:
        raise RuntimeError('рабочие байты родителя изменены')
    return привязки


def проверить_указатель_листа(родитель, цель, путь, раздел):
    каталог, ошибки = исходный.expected_submodule_git_directory(родитель, путь, раздел)
    ошибки += исходный.validate_dependency_worktree_location(родитель, цель, путь)
    if ошибки or каталог is None:
        raise RuntimeError('; '.join(ошибки))
    маркер = цель / '.git'
    текст, _ = исходный.прочитать_метаданные_регистрации(маркер)
    if not текст.startswith('gitdir: ') or not текст[8:]:
        raise RuntimeError('неверный связанный указатель листа')
    сырой = Path(текст[8:])
    физический, _ = исходный.физический_маршрут_указателя(сырой if сырой.is_absolute() else цель / сырой)
    if физический != каталог:
        raise RuntimeError('указатель листа ведёт в иной private GitDir')
    ошибки = исходный.validate_submodule_git_directory(родитель, цель, путь, раздел)
    if ошибки or Path(исходный.run_git(цель, 'rev-parse', '--show-toplevel').stdout) != цель:
        raise RuntimeError('; '.join(ошибки) or 'лист обнаруживает чужой Git-корень')
    if os.path.lexists(каталог / 'commondir') or os.path.lexists(каталог / 'objects/info/alternates'):
        raise RuntimeError('общие или заимствованные объекты листа запрещены')
    return каталог


def проверить_готовность_графа(родитель, граф):
    привязки = проверить_родителя_графа(родитель, граф)
    листья = {лист['путь']: лист for лист in граф['листья']}
    for путь, (раздел, _) in привязки.items():
        цель = родитель.joinpath(*PurePosixPath(путь).parts)
        ошибки = исходный.validate_dependency_worktree_location(родитель, цель, путь)
        каталог, ошибки_каталога = исходный.expected_submodule_git_directory(родитель, путь, раздел)
        if ошибки or ошибки_каталога or каталог is None:
            raise RuntimeError('; '.join(ошибки + ошибки_каталога))
        if путь not in листья:
            if os.path.lexists(каталог) or (os.path.lexists(цель) and (not цель.is_dir() or any(цель.iterdir()))):
                raise RuntimeError('невыбранный узел графа материализован или занят')
            continue
        лист = листья[путь]
        проверить_указатель_листа(родитель, цель, путь, раздел)
        ошибки = []
        суперпроект = исходный.run_git(цель, 'rev-parse', '--show-superproject-working-tree').stdout
        if ошибки or not суперпроект or Path(суперпроект) != родитель:
            raise RuntimeError('; '.join(ошибки) or 'связь листа с родителем неизвестна')
        проверить_полноту(цель)
        ошибки = исходный.проверить_флаги_индекса(цель, путь)
        if (ошибки or исходный.run_git(цель, 'status', '--porcelain=v1', '--untracked-files=all', '--ignored').stdout
                or исходный.run_git(цель, 'rev-parse', 'HEAD').stdout != лист['ревизия']
                or исходный.run_git(цель, 'symbolic-ref', '-q', 'HEAD', allowed_returncodes=(0, 1)).returncode != 1):
            raise RuntimeError('; '.join(ошибки) or 'лист нечист, скрывает индекс или имеет иной HEAD')
        if исходный.run_git(цель, 'rev-parse', 'HEAD^{tree}').stdout != лист['дерево']:
            raise RuntimeError('дерево листа не совпадает с независимым выбором')
        проверить_дерево_графа(цель, лист['ревизия'])
        if исходный.run_git(цель, 'remote').stdout.splitlines() != ['origin', 'upstream']:
            raise RuntimeError('неверные роли remote листа')
        for роль, адрес in (('origin', лист['адрес_форка']), ('upstream', лист['адрес_оригинала'])):
            ошибки = исходный.validate_remote_urls(цель, путь, роль, адрес)
            ошибки += исходный.validate_remote_fetch_refspec(цель, путь, роль)
            ошибки += исходный.validate_remote_has_tracking_refs(цель, путь, роль)
            if ошибки: raise RuntimeError('; '.join(ошибки))
        достижим, ошибки = исходный.remote_revision_is_reachable(цель, лист['ревизия'], 'origin')
        if ошибки or not достижим:
            raise RuntimeError('; '.join(ошибки) or 'pin листа не достижим из origin')


def проверить_запись(корень, запись, ожидаемая=None, граф=None):
    путь, описание = запись['путь'], запись['описание']
    if граф is not None:
        проверить_форму_графа(граф, описание)
    параметры = {'ревизия': описание.revision, 'ожидаемая': ожидаемая}
    зависимость = корень.joinpath(*PurePosixPath(путь).parts)
    ошибки = исходный.validate_dependency_worktree_location(корень, зависимость, путь)
    if ошибки:
        return диагноз(путь, 'небезопасный_путь', причины=ошибки, **параметры)
    маркер = зависимость / '.git'
    if not маркер.exists() and not маркер.is_symlink():
        обнаруженный = 'неизвестно'
        if зависимость.is_dir():
            результат = исходный.run_git(зависимость, 'rev-parse', '--show-toplevel',
                                         allowed_returncodes=(0, 128))
            if результат.returncode == 0:
                обнаруженный = 'суперпроект' if Path(результат.stdout).resolve() == корень else 'чужой'
            if any(зависимость.iterdir()):
                return диагноз(путь, 'занятый_путь', корень_копии=обнаруженный,
                               причины=['нет связанного .git; каталог не пуст'], **параметры)
        if запись['каталог'].exists() or запись['каталог'].is_symlink():
            return диагноз(путь, 'остаток_подготовки', корень_копии=обнаруженный,
                           причины=['остаточный Git-каталог сохраняется'], **параметры)
        адреса, ошибки = исходный.read_nul_config_values(корень, '--get-all', запись['раздел'] + '.url')
        if ошибки or адреса is None:
            raise RuntimeError('; '.join(ошибки) or 'локальный URL неизвестен')
        if адреса not in ([], [описание.fork_url]):
            return диагноз(путь, 'нарушена_регистрация', причины=['неверный или множественный локальный URL'],
                           корень_копии=обнаруженный, **параметры)
        return диагноз(путь, 'не_материализована', корень_копии=обнаруженный,
                       причины=['собственный Git-клон отсутствует'], **параметры)
    if маркер.is_symlink() or not маркер.is_file():
        return диагноз(путь, 'неверная_топология', причины=['нужен обычный связанный .git-файл'], **параметры)
    действительный = Path(исходный.run_git(зависимость, 'rev-parse', '--show-toplevel').stdout).resolve()
    if действительный != зависимость:
        вид = 'суперпроект' if действительный == корень else 'чужой'
        return диагноз(путь, 'неверная_топология', корень_копии=вид,
                       причины=['Git-корень не совпадает с путём зависимости'], **параметры)
    ошибки = исходный.validate_submodule_git_directory(корень, зависимость, путь, запись['раздел'])
    суперпроект = исходный.run_git(зависимость, 'rev-parse', '--show-superproject-working-tree').stdout
    if ошибки or not суперпроект or Path(суперпроект).resolve() != корень:
        return диагноз(путь, 'неверная_топология', причины=ошибки or ['иная связь с суперпроектом'], **параметры)
    параметры['корень_копии'] = 'зависимость'
    try:
        проверить_полноту(зависимость)
    except ОшибкаДопуска as ошибка:
        return диагноз(путь, 'неполная_копия', причины=[str(ошибка)], **параметры)
    ошибки = исходный.проверить_флаги_индекса(зависимость, путь)
    if ошибки:
        return диагноз(путь, 'скрывающие_флаги', причины=ошибки, **параметры)
    if граф is None and any(запись['режим'] == '160000' for запись in индексные_записи(зависимость).values()):
        return диагноз(путь, 'вложенные_зависимости', причины=['вложенный граф не поддерживается'], **параметры)
    if граф is not None:
        проверить_готовность_графа(зависимость, граф)
    параметры['фактическая'] = исходный.run_git(зависимость, 'rev-parse', 'HEAD').stdout
    if исходный.run_git(зависимость, 'status', '--porcelain=v1').stdout:
        return диагноз(путь, 'нечистая_копия', причины=['есть локальные изменения'], **параметры)
    if параметры['фактическая'] != описание.revision or (ожидаемая is not None and ожидаемая != описание.revision):
        return диагноз(путь, 'иная_ревизия', причины=['HEAD или ожидаемая ревизия не совпадает с gitlink'], **параметры)
    ошибки = исходный.validate_dependency(корень, описание)
    if ошибки:
        return диагноз(путь, 'нарушен_контракт', причины=ошибки, **параметры)
    return диагноз(путь, 'готова', **параметры)


def проверить_готовность_зависимости(корень_репозитория, путь, *, ожидаемая_ревизия=None, граф=None):
    try:
        проверить_код()
        корень = нормализовать_корень(корень_репозитория)
        инвентарь = прочитать_инвентарь(корень)
        запись = next((запись for запись in инвентарь if запись['путь'] == путь), None)
        if запись is None:
            return диагноз(путь, 'нет_регистрации', ожидаемая=ожидаемая_ревизия,
                           причины=['точная регистрация пути отсутствует'])
        return проверить_запись(корень, запись, ожидаемая_ревизия, граф)
    except ОшибкаДопуска as ошибка:
        return диагноз(путь, ошибка.состояние, ожидаемая=ожидаемая_ревизия, причины=[str(ошибка)])
    except (OSError, UnicodeError, RuntimeError, ValueError, TypeError, KeyError) as ошибка:
        return диагноз(путь, 'неизвестность', ожидаемая=ожидаемая_ревизия, причины=[str(ошибка)])


def прочитать_набор_графов(ссылка):
    данные = разобрать_объект(исходный.прочитать_закреплённые_байты(ссылка))
    if (type(данные) is not dict or set(данные) != {'схема', 'графы'}
            or данные['схема'] != 'fum.набор-графов-зависимостей.1'
            or type(данные['графы']) is not dict):
        raise RuntimeError('неверная закрытая форма закреплённого набора графов')
    for путь, граф in данные['графы'].items():
        if type(граф) is not dict or type(граф.get('родитель')) is not dict:
            raise RuntimeError('неверная форма графа набора')
        родитель = граф['родитель']
        if (set(родитель) != {'адрес_форка', 'адрес_оригинала', 'путь', 'ревизия'}
                or any(type(значение) is not str for значение in родитель.values())
                or родитель['путь'] != путь):
            raise RuntimeError('ключ набора не совпадает с родителем графа')
        описание = исходный.DependencySpec(*(родитель[ключ] for ключ in
            ('адрес_форка', 'адрес_оригинала', 'путь', 'ревизия')))
        проверить_форму_графа(граф, описание)
    return данные['графы']


def проверить_набор_графов(инвентарь, ссылка):
    графы = {} if ссылка is None else прочитать_набор_графов(ссылка)
    записи = {запись['путь']: запись for запись in инвентарь}
    if set(графы) - set(записи):
        raise RuntimeError('граф набора не связан с текущим инвентарём')
    for путь, граф in графы.items():
        проверить_форму_графа(граф, записи[путь]['описание'])
    return графы


def графы_квитанции(данные):
    return прочитать_набор_графов(данные['набор_графов']) if данные['схема'] == 'fum.подготовка-зависимостей.3' else {}


def проверить_сохранение_графов(прежние, текущие):
    if any(текущие.get(путь) != граф for путь, граф in прежние.items()):
        raise RuntimeError('прежний закреплённый граф утрачен или изменён')


def проверить_зависимости(корень_репозитория, *, графы=None, набор_графов=None):
    проверить_код()
    корень = нормализовать_корень(корень_репозитория)
    инвентарь = прочитать_инвентарь(корень)
    if набор_графов is not None:
        if графы is not None:
            raise RuntimeError('набор и незакреплённая карта графов несовместимы')
        графы = проверить_набор_графов(инвентарь, набор_графов)
    графы = {} if графы is None else графы
    if (type(графы) is not dict or set(графы) - {запись['путь'] for запись in инвентарь}
            or any(type(граф) is not dict or граф.get('схема') != 'fum.граф-зависимости.1' for граф in графы.values())):
        raise RuntimeError('граф не связан с текущим инвентарём')
    результаты = [проверить_запись(корень, запись, граф=графы.get(запись['путь'])) for запись in инвентарь]
    if набор_графов is not None:
        прочитать_набор_графов(набор_графов)
    return {'схема': 'fum.готовность-зависимостей.1',
            'готова': all(результат['готова'] for результат in результаты),
            'зависимости': результаты}


def снять_снимок(корень_репозитория):
    проверить_код()
    корень = нормализовать_корень(корень_репозитория)
    собственный = Path(исходный.run_git(корень, 'rev-parse', '--absolute-git-dir').stdout)
    общий = Path(исходный.run_git(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').stdout)
    индекс = Path(исходный.run_git(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index').stdout)
    return {'схема': 'fum.снимок-окружения-зависимостей.1', 'корень': str(корень),
            'гит_каталог': str(собственный), 'общий_гит_каталог': str(общий),
            'коммит': исходный.run_git(корень, 'rev-parse', 'HEAD').stdout,
            'ссылка': исходный.run_git(корень, 'symbolic-ref', 'HEAD', allowed_returncodes=(0, 1)).stdout,
            'индекс': хэш_файла(индекс),
            'инвентарь_индекса': исходный.run_git(корень, 'ls-files', '--stage', '-v', '-z', strip_output=False).stdout,
            'описание_подмодулей': хэш_файла(корень / '.gitmodules'),
            'конфигурация': хэш_файла(общий / 'config'),
            'конфигурация_дерева': хэш_файла(собственный / 'config.worktree'),
            'код': ОТПЕЧАТОК_КОДА.copy()}


def проверить_владение(корень, снимок, исполнитель, корневая_задача):
    for идентификатор in (исполнитель, корневая_задача):
        if str(uuid.UUID(идентификатор)) != идентификатор:
            raise RuntimeError('нужен точный lowercase UUID')
    if os.environ.get('CODEX_THREAD_ID') != исполнитель:
        raise RuntimeError('отсутствующий или чужой native UUID процесса')
    if снять_снимок(корень) != снимок:
        raise RuntimeError('защищённый снимок изменился')
    ссылка = снимок['ссылка']
    if not (ссылка.startswith('refs/heads/codex/') or ссылка in {'refs/heads/fuma', 'refs/heads/planirovaniye'}):
        raise RuntimeError('неподдерживаемая ветка писателя')
    текст = исходный.run_git(корень, 'worktree', 'list', '--porcelain').stdout
    владельцы = [блок.splitlines()[0].removeprefix('worktree ')
                 for блок in текст.split('\n\n') if 'branch ' + ссылка in блок.splitlines()]
    if владельцы != [str(корень)]:
        raise RuntimeError('неоднозначный владелец дерева или ref')


def прочитать_объект(путь):
    if Path(путь).is_symlink() or not Path(путь).is_file():
        raise RuntimeError('нужен обычный JSON-файл')

    return разобрать_объект(Path(путь).read_bytes())


def разобрать_объект(байты):
    def пары(записи):
        результат = {}
        for ключ, значение in записи:
            if ключ in результат:
                raise RuntimeError('повтор JSON-ключа')
            результат[ключ] = значение
        return результат

    def отказать_константе(значение):
        raise RuntimeError('недопустимая JSON-константа: ' + значение)

    return json.loads(байты.decode('utf-8'), object_pairs_hook=пары,
                      parse_constant=отказать_константе)


КАТАЛОГ_АРХИВА = 'fum-подготовка-зависимостей-архив-v1'


def прочитать_квитанцию(путь):
    путь = Path(путь)
    if путь.resolve() != путь or путь.is_symlink() or not путь.is_file():
        raise RuntimeError('нужен собственный обычный файл квитанции')
    свойства = путь.stat()
    if stat.S_IMODE(свойства.st_mode) != 0o600 or свойства.st_uid != os.geteuid():
        raise RuntimeError('квитанции нужны собственный владелец и режим 0600')
    байты = путь.read_bytes()
    try:
        данные = разобрать_объект(байты)
    except (UnicodeError, ValueError) as ошибка:
        raise RuntimeError('повреждённые JSON-байты квитанции') from ошибка
    return данные, байты


def проверить_хэш(значение):
    return type(значение) is str and re.fullmatch('[0-9a-f]{64}', значение) is not None


def исторические_гитлинки(снимок):
    """Исторический индекс читается как данные; старый код не исполняется."""
    поля = {'схема', 'корень', 'гит_каталог', 'общий_гит_каталог', 'коммит', 'ссылка',
            'индекс', 'инвентарь_индекса', 'описание_подмодулей', 'конфигурация',
            'конфигурация_дерева', 'код'}
    if (type(снимок) is not dict or set(снимок) != поля
            or снимок['схема'] != 'fum.снимок-окружения-зависимостей.1'
            or type(снимок['коммит']) is not str
            or re.fullmatch('[0-9a-f]{40}|[0-9a-f]{64}', снимок['коммит']) is None
            or type(снимок['ссылка']) is not str
            or not (снимок['ссылка'].startswith('refs/heads/codex/')
                    or снимок['ссылка'] in {'refs/heads/fuma', 'refs/heads/planirovaniye'})
            or not проверить_хэш(снимок['индекс'])
            or not проверить_хэш(снимок['конфигурация'])
            or any(снимок[поле] is not None and not проверить_хэш(снимок[поле])
                   for поле in ('описание_подмодулей', 'конфигурация_дерева'))
            or type(снимок['код']) is not dict or set(снимок['код']) != set(ОТПЕЧАТОК_КОДА)
            or any(not проверить_хэш(значение) for значение in снимок['код'].values())):
        raise RuntimeError('повреждённая форма исторического снимка')
    for поле in ('корень', 'гит_каталог', 'общий_гит_каталог'):
        значение = снимок[поле]
        if type(значение) is not str or not Path(значение).is_absolute() or str(Path(значение)) != значение:
            raise RuntimeError('неканонический путь исторического снимка')
    текст = снимок['инвентарь_индекса']
    if type(текст) is not str or (текст and not текст.endswith('\0')):
        raise RuntimeError('неполный исторический NUL-инвентарь')
    записи, зависимости = set(), {}
    for строка in текст.split('\0')[:-1] if текст else []:
        метаданные, разделитель, путь = строка.partition('\t')
        совпадение = re.fullmatch(r'H (100644|100755|120000|160000) ([0-9a-f]{40}|[0-9a-f]{64}) 0', метаданные)
        if (not разделитель or совпадение is None or not путь or путь in записи
                or путь != PurePosixPath(путь).as_posix() or PurePosixPath(путь).is_absolute()
                or any(часть in {'.', '..'} for часть in PurePosixPath(путь).parts)):
            raise RuntimeError('повреждённая историческая запись stage0')
        записи.add(путь)
        if совпадение[1] == '160000':
            if исходный.validate_dependency_path(путь) or any(ord(символ) < 32 or ord(символ) == 127 for символ in путь):
                raise RuntimeError('небезопасный исторический путь зависимости')
            зависимости[путь] = совпадение[2]
    if зависимости and ('.gitmodules' not in записи or снимок['описание_подмодулей'] is None):
        raise RuntimeError('исторические gitlinks не имеют описания')
    return зависимости


def путь_архива(собственный, хэш, *, создать=False):
    if not проверить_хэш(хэш):
        raise RuntimeError('нужен lowercase SHA-256 предшественника')
    каталог = собственный / КАТАЛОГ_АРХИВА
    if создать and not os.path.lexists(каталог):
        каталог.mkdir(mode=0o700)
        синхронизировать_каталог(собственный)
    if (каталог.resolve() != каталог or каталог.is_symlink() or not каталог.is_dir()
            or stat.S_IMODE(каталог.stat().st_mode) != 0o700 or каталог.stat().st_uid != os.geteuid()):
        raise RuntimeError('небезопасный собственный каталог архива')
    return каталог / (хэш + '.json')


def синхронизировать_каталог(каталог):
    дескриптор = os.open(каталог, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def проверить_цепочку(данные, собственный, исполнитель, корневая_задача):
    """Итеративно проверяет каждое звено до v1, включая наследуемый запрет init."""
    if type(данные) is not dict or type(данные.get('снимок')) is not dict:
        raise RuntimeError('повреждённая форма активной квитанции')
    исторические_гитлинки(данные['снимок'])
    исходная_топология = {поле: данные['снимок'][поле]
                         for поле in ('корень', 'гит_каталог', 'общий_гит_каталог', 'ссылка')}
    просмотренные, наследуемые = set(), set()
    текущие = данные
    while True:
        ревизии = исторические_гитлинки(текущие['снимок'])
        проверить_квитанцию(текущие, текущие['снимок'], исполнитель, корневая_задача, set(ревизии))
        if {поле: текущие['снимок'][поле] for поле in исходная_топология} != исходная_топология:
            raise RuntimeError('топология цепочки изменилась')
        текущие_графы = графы_квитанции(текущие)
        if (текущие['схема'] == 'fum.подготовка-зависимостей.1'
                or текущие['схема'] == 'fum.подготовка-зависимостей.3' and текущие['предыдущая_квитанция'] is None):
            return наследуемые
        хэш = текущие['предыдущая_квитанция']['sha256']
        if хэш in просмотренные:
            raise RuntimeError('повтор SHA или цикл в цепочке')
        просмотренные.add(хэш)
        прежние, байты = прочитать_квитанцию(путь_архива(собственный, хэш))
        if hashlib.sha256(байты).hexdigest() != хэш:
            raise RuntimeError('архив не совпадает с SHA предшественника')
        if type(прежние) is not dict or type(прежние.get('снимок')) is not dict:
            raise RuntimeError('повреждённый предшественник')
        старые_ревизии = исторические_гитлинки(прежние['снимок'])
        проверить_квитанцию(прежние, прежние['снимок'], исполнитель, корневая_задача, set(старые_ревизии))
        проверить_сохранение_графов(графы_квитанции(прежние), текущие_графы)
        if not прежние['готова'] or any(состояние != 'готова' for состояние in прежние['состояния'].values()):
            raise RuntimeError('предшественник не финализирован')
        for путь, ревизия in старые_ревизии.items():
            if (ревизии.get(путь) != ревизия or текущие['состояния'].get(путь) != 'готова'
                    or any(событие['путь'] == путь and событие['фаза'] != 'автономное_подтверждение'
                           for событие in текущие['события'])):
                raise RuntimeError('прежний готовый путь или его запрет init утрачен')
        наследуемые.update(старые_ревизии)
        текущие = прежние


def сохранить_архив(собственный, хэш, байты):
    путь = путь_архива(собственный, хэш, создать=True)
    try:
        дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    except FileExistsError:
        _, прежние_байты = прочитать_квитанцию(путь)
        if прежние_байты != байты:
            raise RuntimeError('архив занят другими байтами')
        дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
        try:
            os.fsync(дескриптор)
        finally:
            os.close(дескриптор)
    else:
        with os.fdopen(дескриптор, 'wb') as файл:
            файл.write(байты); файл.flush(); os.fsync(файл.fileno())
    синхронизировать_каталог(путь.parent)
    return путь


def записать_квитанцию(путь, данные):
    проверить_квитанцию(данные, данные['снимок'], данные['исполнитель'],
                       данные['корневая_задача'], set(данные['состояния']))
    проверить_цепочку(данные, путь.parent, данные['исполнитель'], данные['корневая_задача'])
    временный = путь.with_name(путь.name + '.' + str(uuid.uuid4()) + '.tmp')
    дескриптор = os.open(временный, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(дескриптор, 'w', encoding='utf-8') as файл:
        json.dump(данные, файл, ensure_ascii=False, sort_keys=True, indent=2)
        файл.write('\n'); файл.flush(); os.fsync(файл.fileno())
    os.replace(временный, путь)
    дескриптор = os.open(путь.parent, os.O_RDONLY)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def группа_жива(номер):
    if type(номер) is not int or номер <= 0:
        raise RuntimeError('неизвестная прежняя группа процессов')
    try:
        os.killpg(номер, 0)
        return True
    except ProcessLookupError:
        return False
    except PermissionError:
        return True


СОСТОЯНИЯ_ПОПЫТКИ = {'не_начата', 'выполняется', 'не_завершена', 'готова'}
ФАЗЫ_ЭФФЕКТОВ = ('материализация', 'добавление_источника_оригинала',
                 'получение_форка', 'получение_оригинала', 'выбор_ревизии')


def проверить_квитанцию(данные, снимок, исполнитель, корневая_задача, пути):
    поля = {'схема', 'снимок', 'исполнитель', 'корневая_задача', 'группа_процессов',
            'состояния', 'события', 'готова'}
    if type(данные) is dict and данные.get('схема') in {'fum.подготовка-зависимостей.2', 'fum.подготовка-зависимостей.3'}:
        поля |= {'предыдущая_квитанция'}
        предшественник = данные.get('предыдущая_квитанция')
        if not (данные['схема'] == 'fum.подготовка-зависимостей.3' and предшественник is None) and (
                type(предшественник) is not dict or set(предшественник) != {'sha256'}
                or not проверить_хэш(предшественник['sha256'])):
            raise RuntimeError('повреждённая ссылка на предшественника')
    if type(данные) is dict and данные.get('схема') == 'fum.подготовка-зависимостей.3':
        поля |= {'набор_графов'}
        графы = графы_квитанции(данные)
        ревизии = исторические_гитлинки(снимок)
        if any(путь not in пути or ревизии.get(путь) != граф['родитель']['ревизия'] for путь, граф in графы.items()):
            raise RuntimeError('граф квитанции не связан с её stage0-снимком')
    if (type(данные) is not dict or set(данные) != поля
            or данные['схема'] not in {'fum.подготовка-зависимостей.1', 'fum.подготовка-зависимостей.2', 'fum.подготовка-зависимостей.3'}
            or данные['снимок'] != снимок or данные['исполнитель'] != исполнитель
            or данные['корневая_задача'] != корневая_задача
            or type(данные['готова']) is not bool
            or type(данные['группа_процессов']) is not int or данные['группа_процессов'] <= 0
            or type(данные['состояния']) is not dict or set(данные['состояния']) != пути
            or any(type(состояние) is not str or состояние not in СОСТОЯНИЯ_ПОПЫТКИ
                   for состояние in данные['состояния'].values())
            or type(данные['события']) is not list):
        raise RuntimeError('чужая, повреждённая или изменившаяся квитанция')
    состояния = {путь: 'не_начата' for путь in пути}
    фазы, группы = {}, {}
    for событие in данные['события']:
        if (type(событие) is not dict or type(событие.get('путь')) is not str
                or событие['путь'] not in пути or type(событие.get('фаза')) is not str):
            raise RuntimeError('повреждённое событие квитанции')
        путь, фаза = событие['путь'], событие['фаза']
        прежнее = состояния[путь]
        if фаза == 'намерение' or фаза in ФАЗЫ_ЭФФЕКТОВ:
            if (set(событие) != {'путь', 'фаза', 'группа_процессов'}
                    or type(событие['группа_процессов']) is not int or событие['группа_процессов'] <= 0):
                raise RuntimeError('некорректная группа события')
            if фаза == 'намерение':
                if прежнее != 'не_начата':
                    raise RuntimeError('повтор или неверный порядок намерения')
                группы[путь] = событие['группа_процессов']
                фазы[путь] = -1
            else:
                номер = ФАЗЫ_ЭФФЕКТОВ.index(фаза)
                предыдущая = фазы.get(путь, -2)
                if (прежнее != 'выполняется' or событие['группа_процессов'] != группы.get(путь)
                        or not (номер == предыдущая + 1 or (предыдущая == 0 and номер == 2))):
                    raise RuntimeError('нарушена последовательность эффектов')
                фазы[путь] = номер
            состояния[путь] = 'выполняется'
        elif фаза == 'отказ':
            if (set(событие) != {'путь', 'фаза', 'причина'}
                    or type(событие['причина']) is not str or прежнее != 'выполняется'):
                raise RuntimeError('некорректный отказ в истории')
            состояния[путь] = 'не_завершена'
        elif фаза == 'готовность_проверена':
            if (set(событие) != {'путь', 'фаза'} or прежнее != 'выполняется'
                    or фазы.get(путь) != len(ФАЗЫ_ЭФФЕКТОВ) - 1):
                raise RuntimeError('готовность записана без завершения эффекта')
            состояния[путь] = 'готова'
        elif фаза == 'автономное_подтверждение':
            if (set(событие) != {'путь', 'фаза', 'прежнее_состояние', 'прежний_исход_неизвестен'}
                    or событие['прежнее_состояние'] != прежнее
                    or type(событие['прежний_исход_неизвестен']) is not bool
                    or событие['прежний_исход_неизвестен'] != (прежнее in {'выполняется', 'не_завершена'})):
                raise RuntimeError('некорректное автономное подтверждение')
            состояния[путь] = 'готова'
        else:
            raise RuntimeError('неизвестная фаза квитанции')
    if состояния != данные['состояния'] or (данные['готова'] and any(с != 'готова' for с in состояния.values())):
        raise RuntimeError('история и итог квитанции расходятся')


def начать_новую_попытку(корень_репозитория, снимок, исполнитель, корневая_задача,
                         *, ожидаемый_хэш_квитанции, набор_графов=None):
    корень = нормализовать_корень(корень_репозитория)
    проверить_владение(корень, снимок, исполнитель, корневая_задача)
    if not проверить_хэш(ожидаемый_хэш_квитанции):
        raise RuntimeError('нужен независимо закреплённый SHA-256 старой квитанции')
    собственный = Path(снимок['гит_каталог'])
    if собственный.resolve() != собственный or not собственный.is_dir():
        raise RuntimeError('небезопасный собственный Git-каталог')
    квитанция = собственный / 'fum-подготовка-зависимостей-v1.json'
    замок = квитанция.with_suffix('.lock')
    инвентарь = прочитать_инвентарь(корень)
    проверить_набор_графов(инвентарь, набор_графов)

    def допуск():
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        данные, байты = прочитать_квитанцию(квитанция)
        if hashlib.sha256(байты).hexdigest() != ожидаемый_хэш_квитанции:
            raise RuntimeError('активная квитанция не совпадает с ожидаемым SHA-256')
        if type(данные) is not dict or type(данные.get('снимок')) is not dict:
            raise RuntimeError('повреждённая активная квитанция')
        проверить_цепочку(данные, собственный, исполнитель, корневая_задача)
        графы = проверить_набор_графов(инвентарь, набор_графов)
        проверить_сохранение_графов(графы_квитанции(данные), графы)
        if not данные['готова'] or any(состояние != 'готова' for состояние in данные['состояния'].values()):
            raise RuntimeError('прежняя попытка не финализирована')
        if группа_жива(данные['группа_процессов']):
            raise RuntimeError('прежняя группа ещё жива')
        for поле in ('корень', 'гит_каталог', 'общий_гит_каталог', 'ссылка'):
            if данные['снимок'][поле] != снимок[поле]:
                raise RuntimeError('переход не сохраняет идентичность и топологию')
        старые_ревизии = исторические_гитлинки(данные['снимок'])
        текущие_ревизии = исторические_гитлинки(снимок)
        if any(текущие_ревизии.get(путь) != ревизия for путь, ревизия in старые_ревизии.items()):
            raise RuntimeError('прежний путь исчез или его gitlink изменился')
        результаты = [проверить_запись(корень, запись, граф=графы.get(запись['путь'])) for запись in инвентарь]
        if any(результат['состояние'] not in {'готова', 'не_материализована'}
               or (результат['путь'] in старые_ревизии and not результат['готова'])
               or (результат['путь'] in графы and not результат['готова'])
               for результат in результаты):
            raise RuntimeError('инвентарь не допускает перехода; прежняя готовность утрачена')
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        проверить_набор_графов(инвентарь, набор_графов)
        return данные, байты, результаты

    _, прежние_байты, _ = допуск()
    if замок.is_symlink() or (замок.exists() and not замок.is_file()):
        raise RuntimeError('небезопасный путь блокировки')
    дескриптор = os.open(замок, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    try:
        try:
            fcntl.flock(дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as ошибка:
            raise RuntimeError('подготовка уже выполняется') from ошибка
        _, байты, результаты = допуск()
        if байты != прежние_байты:
            raise RuntimeError('квитанция конкурентно изменилась')
        архив = сохранить_архив(собственный, ожидаемый_хэш_квитанции, байты)
        _, проверенные_байты, результаты = допуск()
        if проверенные_байты != байты:
            raise RuntimeError('квитанция изменилась перед установкой')
        данные = {'схема': 'fum.подготовка-зависимостей.2', 'снимок': снимок,
                  'исполнитель': исполнитель, 'корневая_задача': корневая_задача,
                  'группа_процессов': os.getpgrp(), 'состояния': {}, 'события': [],
                  'готова': False, 'предыдущая_квитанция': {'sha256': ожидаемый_хэш_квитанции}}
        if набор_графов is not None:
            данные.update({'схема': 'fum.подготовка-зависимостей.3', 'набор_графов': набор_графов.copy()})
        for результат in результаты:
            путь = результат['путь']
            данные['состояния'][путь] = 'готова' if результат['готова'] else 'не_начата'
            if результат['готова']:
                данные['события'].append({'путь': путь, 'фаза': 'автономное_подтверждение',
                    'прежнее_состояние': 'не_начата', 'прежний_исход_неизвестен': False})
        записать_квитанцию(квитанция, данные)
        return {'схема': 'fum.результат-новой-попытки-зависимостей.1', 'попытка_создана': True,
                'квитанция': str(квитанция), 'архив': str(архив), 'предыдущая_квитанция': {'sha256': ожидаемый_хэш_квитанции}}
    finally:
        os.close(дескриптор)


def подготовить_зависимости(корень_репозитория, снимок, исполнитель, корневая_задача,
                            *, возобновить=False, набор_графов=None):
    корень = нормализовать_корень(корень_репозитория)
    проверить_владение(корень, снимок, исполнитель, корневая_задача)
    инвентарь = прочитать_инвентарь(корень)
    графы = проверить_набор_графов(инвентарь, набор_графов)
    результаты = [проверить_запись(корень, запись, граф=графы.get(запись['путь'])) for запись in инвентарь]
    if any(результат['состояние'] not in {'готова', 'не_материализована'}
           or результат['путь'] in графы and not результат['готова'] for результат in результаты):
        raise RuntimeError('инвентарь содержит неподготовимое состояние: ' +
                           ', '.join(результат['состояние'] for результат in результаты if not результат['готова']))
    собственный = Path(снимок['гит_каталог'])
    if собственный.resolve() != собственный or not собственный.is_dir():
        raise RuntimeError('небезопасный собственный Git-каталог')
    квитанция = собственный / 'fum-подготовка-зависимостей-v1.json'
    замок = собственный / 'fum-подготовка-зависимостей-v1.lock'
    прежняя = None
    прежние_байты = None
    if квитанция.exists() or квитанция.is_symlink():
        прежняя, прежние_байты = прочитать_квитанцию(квитанция)
        проверить_квитанцию(прежняя, снимок, исполнитель, корневая_задача,
                           {запись['путь'] for запись in инвентарь})
        проверить_цепочку(прежняя, собственный, исполнитель, корневая_задача)
        if ((прежняя['схема'] == 'fum.подготовка-зависимостей.3') != (набор_графов is not None)
                or набор_графов is not None and прежняя['набор_графов'] != набор_графов):
            raise RuntimeError('повтор требует прежний закреплённый набор; миграция только через новую попытку')
        if any(прежняя['состояния'][результат['путь']] == 'готова' and not результат['готова']
               for результат in результаты):
            raise RuntimeError('прежде готовая копия изменилась; новая инициализация запрещена')
        незавершённые = {путь for путь, состояние in прежняя['состояния'].items()
                        if состояние in {'выполняется', 'не_завершена'}}
        if незавершённые:
            if not возобновить or группа_жива(прежняя['группа_процессов']):
                raise RuntimeError('незавершённая попытка: нужен явный допуск после остановки её группы')
            if any(not результат['готова'] for результат in результаты if результат['путь'] in незавершённые):
                raise RuntimeError('исход неизвестен; готовность не подтверждена; повтор init запрещён')
        elif возобновить:
            raise RuntimeError('нет незавершённой попытки для возобновления')
    elif возобновить:
        raise RuntimeError('квитанция для возобновления отсутствует')
    if os.getpid() != os.getpgrp():
        raise RuntimeError('подготовке нужна собственная группа процессов; используйте CLI')
    if замок.is_symlink() or (замок.exists() and not замок.is_file()):
        raise RuntimeError('небезопасный путь блокировки')
    дескриптор = os.open(замок, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    try:
        try:
            fcntl.flock(дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as ошибка:
            raise RuntimeError('подготовка уже выполняется') from ошибка
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        графы = проверить_набор_графов(инвентарь, набор_графов)
        if (прочитать_квитанцию(квитанция)[1] if os.path.lexists(квитанция) else None) != прежние_байты:
            raise RuntimeError('квитанция конкурентно изменилась')
        if прежняя is not None:
            проверить_квитанцию(прежняя, снимок, исполнитель, корневая_задача,
                               {запись['путь'] for запись in инвентарь})
            проверить_цепочку(прежняя, собственный, исполнитель, корневая_задача)
        if прежняя is not None and прежняя['готова']:
            итог = проверить_зависимости(корень, набор_графов=набор_графов)
            проверить_владение(корень, снимок, исполнитель, корневая_задача)
            проверить_набор_графов(инвентарь, набор_графов)
            if not итог['готова']:
                raise RuntimeError('готовый повтор утратил готовность')
            return {'схема': 'fum.результат-подготовки-зависимостей.1', 'готова': True,
                    'квитанция': str(квитанция), 'зависимости': итог['зависимости'],
                    'без_повторных_эффектов': True}
        данные = прежняя or {'схема': 'fum.подготовка-зависимостей.1', 'снимок': снимок,
                    'исполнитель': исполнитель, 'корневая_задача': корневая_задача,
                    'группа_процессов': os.getpgrp(), 'состояния': {запись['путь']: 'не_начата' for запись in инвентарь},
                    'события': [], 'готова': False}
        if прежняя is None and набор_графов is not None:
            данные.update({'схема': 'fum.подготовка-зависимостей.3', 'набор_графов': набор_графов.copy(),
                           'предыдущая_квитанция': None})
        данные['группа_процессов'] = os.getpgrp()
        for запись in инвентарь:
            путь = запись['путь']
            графы = проверить_набор_графов(инвентарь, набор_графов)
            готовность = проверить_запись(корень, запись, граф=графы.get(путь))
            if готовность['готова']:
                прежнее_состояние = данные['состояния'][путь]
                данные['состояния'][путь] = 'готова'
                данные['события'].append({'путь': путь, 'фаза': 'автономное_подтверждение',
                    'прежнее_состояние': прежнее_состояние, 'прежний_исход_неизвестен': прежнее_состояние in {'выполняется', 'не_завершена'}})
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
                записать_квитанцию(квитанция, данные)
                continue
            if готовность['состояние'] != 'не_материализована' or данные['состояния'][путь] != 'не_начата':
                raise RuntimeError('попытка не допускает нового init')

            def перед_эффектом(фаза):
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
                проверить_цепочку(данные, собственный, исполнитель, корневая_задача)
                графы_перед_эффектом = проверить_набор_графов(инвентарь, набор_графов)
                for защищённая in инвентарь:
                    if (данные['состояния'][защищённая['путь']] == 'готова'
                            and not проверить_запись(корень, защищённая,
                                граф=графы_перед_эффектом.get(защищённая['путь']))['готова']):
                        raise RuntimeError('прежде готовая копия изменилась перед эффектом; init запрещён')
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
                данные['состояния'][путь] = 'выполняется'
                данные['события'].append({'путь': путь, 'фаза': фаза, 'группа_процессов': os.getpgrp()})
                записать_квитанцию(квитанция, данные)

            перед_эффектом('намерение')
            try:
                _, ошибки = исходный.initialize_registered_dependency(корень, путь, перед_эффектом=перед_эффектом)
                графы = проверить_набор_графов(инвентарь, набор_графов)
                готовность = проверить_запись(корень, запись, граф=графы.get(путь))
                if ошибки or not готовность['готова']:
                    raise RuntimeError('; '.join(ошибки) or готовность['состояние'])
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
            except BaseException as ошибка:
                данные['состояния'][путь] = 'не_завершена'
                данные['события'].append({'путь': путь, 'фаза': 'отказ', 'причина': str(ошибка)})
                записать_квитанцию(квитанция, данные)
                raise
            данные['состояния'][путь] = 'готова'
            данные['события'].append({'путь': путь, 'фаза': 'готовность_проверена'})
            записать_квитанцию(квитанция, данные)
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        итог = проверить_зависимости(корень, набор_графов=набор_графов)
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        проверить_набор_графов(инвентарь, набор_графов)
        if not итог['готова']:
            raise RuntimeError('итоговая готовность не подтверждена')
        данные['готова'] = True
        записать_квитанцию(квитанция, данные)
        return {'схема': 'fum.результат-подготовки-зависимостей.1', 'готова': True,
                'квитанция': str(квитанция), 'зависимости': итог['зависимости'], 'без_повторных_эффектов': False}
    finally:
        os.close(дескриптор)


def выполнить_команду():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('команда', choices=['готовность', 'проверить', 'снимок', 'подготовить', 'возобновить', 'новая-попытка'])
    разбор.add_argument('--корень-репозитория', required=True)
    разбор.add_argument('--путь')
    разбор.add_argument('--ожидаемая-ревизия')
    разбор.add_argument('--снимок')
    разбор.add_argument('--исполнитель')
    разбор.add_argument('--корневая-задача')
    разбор.add_argument('--ожидаемый-хэш-квитанции')
    разбор.add_argument('--граф')
    разбор.add_argument('--ожидаемый-хэш-графа')
    разбор.add_argument('--набор-графов')
    разбор.add_argument('--ожидаемый-хэш-набора-графов')
    параметры = разбор.parse_args()
    try:
        граф = None
        набор = None
        if параметры.набор_графов is not None or параметры.ожидаемый_хэш_набора_графов is not None:
            if (not all((параметры.набор_графов, параметры.ожидаемый_хэш_набора_графов))
                    or параметры.команда == 'снимок' or параметры.граф is not None
                    or параметры.ожидаемый_хэш_графа is not None):
                raise RuntimeError('набор графов требует отдельный SHA-256 и несовместим с одиночным графом или снимком')
            набор = {'путь': параметры.набор_графов, 'хэш_байтов': параметры.ожидаемый_хэш_набора_графов}
            прочитать_набор_графов(набор)
        if параметры.граф is not None or параметры.ожидаемый_хэш_графа is not None:
            if параметры.команда not in ('готовность', 'проверить') or not all((параметры.граф, параметры.ожидаемый_хэш_графа)):
                raise RuntimeError('граф допускается только для читающей проверки с отдельно выбранным SHA-256')
            граф = разобрать_объект(исходный.прочитать_закреплённые_байты(
                {'путь': параметры.граф, 'хэш_байтов': параметры.ожидаемый_хэш_графа}))
            if type(граф) is not dict or граф.get('схема') != 'fum.граф-зависимости.1':
                raise RuntimeError('явно выбранный граф должен иметь закрытую версию .1')
        if параметры.команда == 'готовность':
            if not параметры.путь:
                raise RuntimeError('готовность требует --путь')
            if набор is not None:
                граф = проверить_набор_графов(прочитать_инвентарь(
                    нормализовать_корень(параметры.корень_репозитория)), набор).get(параметры.путь)
            результат = проверить_готовность_зависимости(параметры.корень_репозитория, параметры.путь,
                                                        ожидаемая_ревизия=параметры.ожидаемая_ревизия, граф=граф)
        elif параметры.команда == 'проверить':
            результат = проверить_зависимости(параметры.корень_репозитория,
                графы={граф['родитель']['путь']: граф} if граф is not None else None, набор_графов=набор)
        elif параметры.команда == 'снимок':
            результат = снять_снимок(параметры.корень_репозитория)
        else:
            if not all((параметры.снимок, параметры.исполнитель, параметры.корневая_задача)):
                raise RuntimeError('подготовка требует снимок и оба UUID')
            if os.getpid() != os.getpgrp():
                os.setsid()
            if параметры.команда == 'новая-попытка':
                результат = начать_новую_попытку(параметры.корень_репозитория, прочитать_объект(параметры.снимок),
                    параметры.исполнитель, параметры.корневая_задача,
                    ожидаемый_хэш_квитанции=параметры.ожидаемый_хэш_квитанции, набор_графов=набор)
            else:
                результат = подготовить_зависимости(параметры.корень_репозитория, прочитать_объект(параметры.снимок),
                    параметры.исполнитель, параметры.корневая_задача, возобновить=параметры.команда == 'возобновить',
                    набор_графов=набор)
        if набор is not None:
            прочитать_набор_графов(набор)
        print(json.dumps(результат, ensure_ascii=False, sort_keys=True))
        if результат.get('состояние') == 'неизвестность':
            return 2
        return 0 if результат.get('готова', True) else 1
    except ОшибкаДопуска as ошибка:
        print(json.dumps({'схема': 'fum.отказ-подготовки-зависимостей.1', 'готова': False,
                          'состояние': ошибка.состояние, 'причина': str(ошибка)}, ensure_ascii=False))
        return 1
    except (OSError, UnicodeError, RuntimeError, ValueError, TypeError, KeyError) as ошибка:
        print(json.dumps({'схема': 'fum.отказ-подготовки-зависимостей.1', 'готова': False,
                          'причина': str(ошибка)}, ensure_ascii=False))
        return 2


if __name__ == '__main__':
    raise SystemExit(выполнить_команду())

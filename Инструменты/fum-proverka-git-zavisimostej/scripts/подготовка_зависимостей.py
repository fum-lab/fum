байты_исходного = ПУТЬ_ИСХОДНОГО.read_bytes()
if hashlib.sha256(байты_исходного).hexdigest() != ОТПЕЧАТОК_КОДА[ПУТЬ_ИСХОДНОГО.name]:
    raise RuntimeError('код валидатора изменился при загрузке')
exec(compile(байты_исходного, str(ПУТЬ_ИСХОДНОГО), 'exec'), исходный.__dict__)
исходный.ПРОБРАСЫВАТЬ_ОШИБКИ_ЧТЕНИЯ = True
исходное_исполнение_гит = исходный.run_git



def проверить_полноту(корень):
    результат = исходный.run_git(корень, 'config', '--get-regexp',
        r'^(extensions\.partialclone|remote\..*\.(promisor|partialclonefilter))$',
        allowed_returncodes=(0, 1))
    if результат.returncode == 0:
        raise ОшибкаДопуска('неполная_копия', 'partial/promisor-копия не поддерживается')
    if исходный.run_git(корень, 'rev-parse', '--is-shallow-repository').stdout != 'false':
        raise ОшибкаДопуска('неполная_копия', 'shallow-копия не поддерживается')


def нормализовать_корень(корень):
    путь = Path(корень).absolute()
    if путь.resolve() != путь:
        raise RuntimeError('корень не должен проходить через символические ссылки')
    ошибки = исходный.validate_repo_root(путь)
    if ошибки:
        raise ОшибкаДопуска('неверная_топология', '; '.join(ошибки))
    проверить_полноту(путь)
    return путь


def индексные_записи(корень):
    текст = исходный.run_git(корень, 'ls-files', '--stage', '-z', strip_output=False).stdout
    if текст and not текст.endswith('\0'):
        raise ОшибкаДопуска('нарушен_индекс', 'некорректный NUL-инвентарь индекса')
    записи = {}
    for строка in текст.split('\0'):
        if not строка:
            continue
        метаданные, разделитель, путь = строка.partition('\t')
        поля = метаданные.split()
        if not разделитель or len(поля) != 3 or поля[2] != '0' or путь in записи:
            raise ОшибкаДопуска('нарушен_индекс', 'конфликтующий или некорректный индекс')
        записи[путь] = {'режим': поля[0], 'ревизия': поля[1]}
    return записи


def прочитать_инвентарь(корень):
    корень = нормализовать_корень(корень)
    ошибки = исходный.проверить_флаги_индекса(корень, 'суперпроект')
    if ошибки:
        raise ОшибкаДопуска('скрывающие_флаги', '; '.join(ошибки))
    записи = индексные_записи(корень)
    пути = {путь for путь, запись in записи.items() if запись['режим'] == '160000'}
    файл = корень / '.gitmodules'
    if '.gitmodules' not in записи and not файл.exists() and not файл.is_symlink():
        if пути:
            raise ОшибкаДопуска('нарушена_регистрация', 'gitlinks не имеют .gitmodules')
        return []
    if файл.is_symlink() or not файл.is_file() or записи.get('.gitmodules', {}).get('режим') != '100644':
        raise ОшибкаДопуска('нарушена_регистрация', '.gitmodules должна быть обычным индексированным файлом')
    файл.read_text(encoding='utf-8')
    ревизия = исходный.run_git(корень, 'hash-object', '--no-filters', '--', '.gitmodules').stdout
    if ревизия != записи['.gitmodules']['ревизия']:
        raise ОшибкаДопуска('нарушена_регистрация', '.gitmodules не совпадает с точным blob индекса')
    результат = исходный.run_git(корень, 'config', '--no-includes', '-z', '-f', '.gitmodules',
                                 '--list', strip_output=False)
    разделы = {}
    for строка in результат.stdout.split('\0'):
        if not строка:
            continue
        ключ, разделитель, значение = строка.partition('\n')
        раздел, точка, поле = ключ.rpartition('.')
        if not разделитель or not точка or not раздел.startswith('submodule.'):
            raise ОшибкаДопуска('нарушена_регистрация', 'посторонняя или некорректная запись .gitmodules')
        разделы.setdefault(раздел, {}).setdefault(поле, []).append(значение)
    регистрации = {}
    for раздел, поля in разделы.items():
        for поле in ('path', 'url', 'fumupstream'):
            значения = поля.get(поле, [])
            if len(значения) != 1 or not значения[0].strip():
                raise ОшибкаДопуска('нарушена_регистрация', 'каждой секции нужны единственные path/url/fumUpstream')
        путь = поля['path'][0]
        if путь in регистрации:
            raise ОшибкаДопуска('нарушена_регистрация', 'неоднозначный инвентарь .gitmodules')
        регистрации[путь] = раздел
    if set(регистрации) != пути:
        raise ОшибкаДопуска('нарушена_регистрация', 'инвентарь .gitmodules не совпадает со stage0 gitlinks')
    инвентарь = []
    for путь in sorted(пути):
        if (исходный.validate_dependency_path(путь) or путь != PurePosixPath(путь).as_posix()
                or any(ord(символ) < 32 or ord(символ) == 127 for символ in путь)):
            raise ОшибкаДопуска('небезопасный_путь', 'небезопасный путь в инвентаре')
        описание, ошибки = исходный.registered_dependency_spec(корень, путь)
        if описание is None or ошибки:
            raise ОшибкаДопуска('нарушена_регистрация', '; '.join(ошибки) or 'нарушена регистрация')
        каталог, ошибки = исходный.expected_submodule_git_directory(корень, путь, регистрации[путь])
        if каталог is None or ошибки:
            raise ОшибкаДопуска('небезопасный_путь', '; '.join(ошибки) or 'неизвестный Git-каталог')
        инвентарь.append({'путь': путь, 'раздел': регистрации[путь], 'описание': описание,
                          'каталог': каталог})
    for номер, запись in enumerate(инвентарь):
        for другая in инвентарь[номер + 1:]:
            for левый, правый in ((запись['путь'], другая['путь']),
                                  (str(запись['каталог']), str(другая['каталог']))):
                левый, правый = левый.casefold(), правый.casefold()
                if левый == правый or левый.startswith(правый + '/') or правый.startswith(левый + '/'):
                    raise ОшибкаДопуска('небезопасный_путь', 'пути зависимостей или Git-каталогов пересекаются')
    return инвентарь


def диагноз(путь, состояние, *, ревизия=None, ожидаемая=None, фактическая=None,
            корень_копии='неизвестно', причины=()):
    return {'схема': 'fum.готовность-зависимости.1', 'путь': путь,
            'готова': состояние == 'готова', 'состояние': состояние,
            'ревизия_индекса': ревизия, 'ожидаемая_ревизия': ожидаемая,
            'фактическая_ревизия': фактическая, 'корень_копии': корень_копии,
            'причины': [{'вид': состояние, 'проверка': причина} for причина in причины]}


def проверить_запись(корень, запись, ожидаемая=None):
    путь, описание = запись['путь'], запись['описание']
    параметры = {'ревизия': описание.revision, 'ожидаемая': ожидаемая}
    зависимость = корень.joinpath(*PurePosixPath(путь).parts)
    ошибки = исходный.validate_dependency_worktree_location(корень, зависимость, путь)
    if ошибки:
        return диагноз(путь, 'небезопасный_путь', причины=ошибки, **параметры)
    маркер = зависимость / '.git'
    if not маркер.exists() and not маркер.is_symlink():
        обнаруженный = 'неизвестно'
        if зависимость.is_dir():
            результат = исходный.run_git(зависимость, 'rev-parse', '--show-toplevel',
                                         allowed_returncodes=(0, 128))
            if результат.returncode == 0:
                обнаруженный = 'суперпроект' if Path(результат.stdout).resolve() == корень else 'чужой'
            if any(зависимость.iterdir()):
                return диагноз(путь, 'занятый_путь', корень_копии=обнаруженный,
                               причины=['нет связанного .git; каталог не пуст'], **параметры)
        if запись['каталог'].exists() or запись['каталог'].is_symlink():
            return диагноз(путь, 'остаток_подготовки', корень_копии=обнаруженный,
                           причины=['остаточный Git-каталог сохраняется'], **параметры)
        адреса, ошибки = исходный.read_nul_config_values(корень, '--get-all', запись['раздел'] + '.url')
        if ошибки or адреса is None:
            raise RuntimeError('; '.join(ошибки) or 'локальный URL неизвестен')
        if адреса not in ([], [описание.fork_url]):
            return диагноз(путь, 'нарушена_регистрация', причины=['неверный или множественный локальный URL'],
                           корень_копии=обнаруженный, **параметры)
        return диагноз(путь, 'не_материализована', корень_копии=обнаруженный,
                       причины=['собственный Git-клон отсутствует'], **параметры)
    if маркер.is_symlink() or not маркер.is_file():
        return диагноз(путь, 'неверная_топология', причины=['нужен обычный связанный .git-файл'], **параметры)
    действительный = Path(исходный.run_git(зависимость, 'rev-parse', '--show-toplevel').stdout).resolve()
    if действительный != зависимость:
        вид = 'суперпроект' if действительный == корень else 'чужой'
        return диагноз(путь, 'неверная_топология', корень_копии=вид,
                       причины=['Git-корень не совпадает с путём зависимости'], **параметры)
    ошибки = исходный.validate_submodule_git_directory(корень, зависимость, путь, запись['раздел'])
    суперпроект = исходный.run_git(зависимость, 'rev-parse', '--show-superproject-working-tree').stdout
    if ошибки or not суперпроект or Path(суперпроект).resolve() != корень:
        return диагноз(путь, 'неверная_топология', причины=ошибки or ['иная связь с суперпроектом'], **параметры)
    параметры['корень_копии'] = 'зависимость'
    try:
        проверить_полноту(зависимость)
    except ОшибкаДопуска as ошибка:
        return диагноз(путь, 'неполная_копия', причины=[str(ошибка)], **параметры)
    ошибки = исходный.проверить_флаги_индекса(зависимость, путь)
    if ошибки:
        return диагноз(путь, 'скрывающие_флаги', причины=ошибки, **параметры)
    if any(запись['режим'] == '160000' for запись in индексные_записи(зависимость).values()):
        return диагноз(путь, 'вложенные_зависимости', причины=['вложенный граф не поддерживается'], **параметры)
    параметры['фактическая'] = исходный.run_git(зависимость, 'rev-parse', 'HEAD').stdout
    if исходный.run_git(зависимость, 'status', '--porcelain=v1').stdout:
        return диагноз(путь, 'нечистая_копия', причины=['есть локальные изменения'], **параметры)
    if параметры['фактическая'] != описание.revision or (ожидаемая is not None and ожидаемая != описание.revision):
        return диагноз(путь, 'иная_ревизия', причины=['HEAD или ожидаемая ревизия не совпадает с gitlink'], **параметры)
    ошибки = исходный.validate_dependency(корень, описание)
    if ошибки:
        return диагноз(путь, 'нарушен_контракт', причины=ошибки, **параметры)
    return диагноз(путь, 'готова', **параметры)


def проверить_готовность_зависимости(корень_репозитория, путь, *, ожидаемая_ревизия=None):
    try:
        проверить_код()
        корень = нормализовать_корень(корень_репозитория)
        инвентарь = прочитать_инвентарь(корень)
        запись = next((запись for запись in инвентарь if запись['путь'] == путь), None)
        if запись is None:
            return диагноз(путь, 'нет_регистрации', ожидаемая=ожидаемая_ревизия,
                           причины=['точная регистрация пути отсутствует'])
        return проверить_запись(корень, запись, ожидаемая_ревизия)
    except ОшибкаДопуска as ошибка:
        return диагноз(путь, ошибка.состояние, ожидаемая=ожидаемая_ревизия, причины=[str(ошибка)])
    except (OSError, UnicodeError, RuntimeError, ValueError) as ошибка:
        return диагноз(путь, 'неизвестность', ожидаемая=ожидаемая_ревизия, причины=[str(ошибка)])


def проверить_зависимости(корень_репозитория):
    проверить_код()
    корень = нормализовать_корень(корень_репозитория)
    инвентарь = прочитать_инвентарь(корень)
    результаты = [проверить_запись(корень, запись) for запись in инвентарь]
    return {'схема': 'fum.готовность-зависимостей.1',
            'готова': all(результат['готова'] for результат in результаты),
            'зависимости': результаты}


def снять_снимок(корень_репозитория):
    проверить_код()
    корень = нормализовать_корень(корень_репозитория)
    собственный = Path(исходный.run_git(корень, 'rev-parse', '--absolute-git-dir').stdout)
    общий = Path(исходный.run_git(корень, 'rev-parse', '--path-format=absolute', '--git-common-dir').stdout)
    индекс = Path(исходный.run_git(корень, 'rev-parse', '--path-format=absolute', '--git-path', 'index').stdout)
    return {'схема': 'fum.снимок-окружения-зависимостей.1', 'корень': str(корень),
            'гит_каталог': str(собственный), 'общий_гит_каталог': str(общий),
            'коммит': исходный.run_git(корень, 'rev-parse', 'HEAD').stdout,
            'ссылка': исходный.run_git(корень, 'symbolic-ref', 'HEAD', allowed_returncodes=(0, 1)).stdout,
            'индекс': хэш_файла(индекс),
            'инвентарь_индекса': исходный.run_git(корень, 'ls-files', '--stage', '-v', '-z', strip_output=False).stdout,
            'описание_подмодулей': хэш_файла(корень / '.gitmodules'),
            'конфигурация': хэш_файла(общий / 'config'),
            'конфигурация_дерева': хэш_файла(собственный / 'config.worktree'),
            'код': ОТПЕЧАТОК_КОДА.copy()}


def проверить_владение(корень, снимок, исполнитель, корневая_задача):
    for идентификатор in (исполнитель, корневая_задача):
        if str(uuid.UUID(идентификатор)) != идентификатор:
            raise RuntimeError('нужен точный lowercase UUID')
    if os.environ.get('CODEX_THREAD_ID') != исполнитель:
        raise RuntimeError('отсутствующий или чужой native UUID процесса')
    if снять_снимок(корень) != снимок:
        raise RuntimeError('защищённый снимок изменился')
    ссылка = снимок['ссылка']
    if not (ссылка.startswith('refs/heads/codex/') or ссылка in {'refs/heads/fuma', 'refs/heads/planirovaniye'}):
        raise RuntimeError('неподдерживаемая ветка писателя')
    текст = исходный.run_git(корень, 'worktree', 'list', '--porcelain').stdout
    владельцы = [блок.splitlines()[0].removeprefix('worktree ')
                 for блок in текст.split('\n\n') if 'branch ' + ссылка in блок.splitlines()]
    if владельцы != [str(корень)]:
        raise RuntimeError('неоднозначный владелец дерева или ref')


def прочитать_объект(путь):
    if Path(путь).is_symlink() or not Path(путь).is_file():
        raise RuntimeError('нужен обычный JSON-файл')

    def пары(записи):
        результат = {}
        for ключ, значение in записи:
            if ключ in результат:
                raise RuntimeError('повтор JSON-ключа')
            результат[ключ] = значение
        return результат

    def отказать_константе(значение):
        raise RuntimeError('недопустимая JSON-константа: ' + значение)

    return json.loads(Path(путь).read_text(encoding='utf-8'), object_pairs_hook=пары,
                      parse_constant=отказать_константе)


def записать_квитанцию(путь, данные):
    проверить_квитанцию(данные, данные['снимок'], данные['исполнитель'],
                       данные['корневая_задача'], set(данные['состояния']))
    временный = путь.with_name(путь.name + '.' + str(uuid.uuid4()) + '.tmp')
    дескриптор = os.open(временный, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(дескриптор, 'w', encoding='utf-8') as файл:
        json.dump(данные, файл, ensure_ascii=False, sort_keys=True, indent=2)
        файл.write('\n'); файл.flush(); os.fsync(файл.fileno())
    os.replace(временный, путь)
    дескриптор = os.open(путь.parent, os.O_RDONLY)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def группа_жива(номер):
    if type(номер) is not int or номер <= 0:
        raise RuntimeError('неизвестная прежняя группа процессов')
    try:
        os.killpg(номер, 0)
        return True
    except ProcessLookupError:
        return False
    except PermissionError:
        return True


СОСТОЯНИЯ_ПОПЫТКИ = {'не_начата', 'выполняется', 'не_завершена', 'готова'}
ФАЗЫ_ЭФФЕКТОВ = ('материализация', 'добавление_источника_оригинала',
                 'получение_форка', 'получение_оригинала', 'выбор_ревизии')


def проверить_квитанцию(данные, снимок, исполнитель, корневая_задача, пути):
    поля = {'схема', 'снимок', 'исполнитель', 'корневая_задача', 'группа_процессов',
            'состояния', 'события', 'готова'}
    if (type(данные) is not dict or set(данные) != поля
            or данные['схема'] != 'fum.подготовка-зависимостей.1'
            or данные['снимок'] != снимок or данные['исполнитель'] != исполнитель
            or данные['корневая_задача'] != корневая_задача
            or type(данные['готова']) is not bool
            or type(данные['группа_процессов']) is not int or данные['группа_процессов'] <= 0
            or type(данные['состояния']) is not dict or set(данные['состояния']) != пути
            or any(type(состояние) is not str or состояние not in СОСТОЯНИЯ_ПОПЫТКИ
                   for состояние in данные['состояния'].values())
            or type(данные['события']) is not list):
        raise RuntimeError('чужая, повреждённая или изменившаяся квитанция')
    состояния = {путь: 'не_начата' for путь in пути}
    фазы, группы = {}, {}
    for событие in данные['события']:
        if (type(событие) is not dict or type(событие.get('путь')) is not str
                or событие['путь'] not in пути or type(событие.get('фаза')) is not str):
            raise RuntimeError('повреждённое событие квитанции')
        путь, фаза = событие['путь'], событие['фаза']
        прежнее = состояния[путь]
        if фаза == 'намерение' or фаза in ФАЗЫ_ЭФФЕКТОВ:
            if (set(событие) != {'путь', 'фаза', 'группа_процессов'}
                    or type(событие['группа_процессов']) is not int or событие['группа_процессов'] <= 0):
                raise RuntimeError('некорректная группа события')
            if фаза == 'намерение':
                if прежнее != 'не_начата':
                    raise RuntimeError('повтор или неверный порядок намерения')
                группы[путь] = событие['группа_процессов']
                фазы[путь] = -1
            else:
                номер = ФАЗЫ_ЭФФЕКТОВ.index(фаза)
                предыдущая = фазы.get(путь, -2)
                if (прежнее != 'выполняется' or событие['группа_процессов'] != группы.get(путь)
                        or not (номер == предыдущая + 1 or (предыдущая == 0 and номер == 2))):
                    raise RuntimeError('нарушена последовательность эффектов')
                фазы[путь] = номер
            состояния[путь] = 'выполняется'
        elif фаза == 'отказ':
            if (set(событие) != {'путь', 'фаза', 'причина'}
                    or type(событие['причина']) is not str or прежнее != 'выполняется'):
                raise RuntimeError('некорректный отказ в истории')
            состояния[путь] = 'не_завершена'
        elif фаза == 'готовность_проверена':
            if (set(событие) != {'путь', 'фаза'} or прежнее != 'выполняется'
                    or фазы.get(путь) != len(ФАЗЫ_ЭФФЕКТОВ) - 1):
                raise RuntimeError('готовность записана без завершения эффекта')
            состояния[путь] = 'готова'
        elif фаза == 'автономное_подтверждение':
            if (set(событие) != {'путь', 'фаза', 'прежнее_состояние', 'прежний_исход_неизвестен'}
                    or событие['прежнее_состояние'] != прежнее
                    or type(событие['прежний_исход_неизвестен']) is not bool
                    or событие['прежний_исход_неизвестен'] != (прежнее in {'выполняется', 'не_завершена'})):
                raise RuntimeError('некорректное автономное подтверждение')
            состояния[путь] = 'готова'
        else:
            raise RuntimeError('неизвестная фаза квитанции')
    if состояния != данные['состояния'] or (данные['готова'] and any(с != 'готова' for с in состояния.values())):
        raise RuntimeError('история и итог квитанции расходятся')


def подготовить_зависимости(корень_репозитория, снимок, исполнитель, корневая_задача,
                            *, возобновить=False):
    корень = нормализовать_корень(корень_репозитория)
    проверить_владение(корень, снимок, исполнитель, корневая_задача)
    инвентарь = прочитать_инвентарь(корень)
    результаты = [проверить_запись(корень, запись) for запись in инвентарь]
    if any(результат['состояние'] not in {'готова', 'не_материализована'} for результат in результаты):
        raise RuntimeError('инвентарь содержит неподготовимое состояние: ' +
                           ', '.join(результат['состояние'] for результат in результаты if not результат['готова']))
    собственный = Path(снимок['гит_каталог'])
    if собственный.resolve() != собственный or not собственный.is_dir():
        raise RuntimeError('небезопасный собственный Git-каталог')
    квитанция = собственный / 'fum-подготовка-зависимостей-v1.json'
    замок = собственный / 'fum-подготовка-зависимостей-v1.lock'
    прежняя = None
    if квитанция.exists() or квитанция.is_symlink():
        прежняя = прочитать_объект(квитанция)
        проверить_квитанцию(прежняя, снимок, исполнитель, корневая_задача,
                           {запись['путь'] for запись in инвентарь})
        if any(прежняя['состояния'][результат['путь']] == 'готова' and not результат['готова']
               for результат in результаты):
            raise RuntimeError('прежде готовая копия изменилась; новая инициализация запрещена')
        незавершённые = {путь for путь, состояние in прежняя['состояния'].items()
                        if состояние in {'выполняется', 'не_завершена'}}
        if незавершённые:
            if not возобновить or группа_жива(прежняя['группа_процессов']):
                raise RuntimeError('незавершённая попытка: нужен явный допуск после остановки её группы')
            if any(not результат['готова'] for результат in результаты if результат['путь'] in незавершённые):
                raise RuntimeError('исход неизвестен; готовность не подтверждена; повтор init запрещён')
        elif возобновить:
            raise RuntimeError('нет незавершённой попытки для возобновления')
    elif возобновить:
        raise RuntimeError('квитанция для возобновления отсутствует')
    if os.getpid() != os.getpgrp():
        raise RuntimeError('подготовке нужна собственная группа процессов; используйте CLI')
    if замок.is_symlink() or (замок.exists() and not замок.is_file()):
        raise RuntimeError('небезопасный путь блокировки')
    дескриптор = os.open(замок, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    try:
        try:
            fcntl.flock(дескриптор, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as ошибка:
            raise RuntimeError('подготовка уже выполняется') from ошибка
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        if (прочитать_объект(квитанция) if квитанция.exists() else None) != прежняя:
            raise RuntimeError('квитанция конкурентно изменилась')
        if прежняя is not None:
            проверить_квитанцию(прежняя, снимок, исполнитель, корневая_задача,
                               {запись['путь'] for запись in инвентарь})
        if прежняя is not None and прежняя['готова']:
            итог = проверить_зависимости(корень)
            проверить_владение(корень, снимок, исполнитель, корневая_задача)
            if not итог['готова']:
                raise RuntimeError('готовый повтор утратил готовность')
            return {'схема': 'fum.результат-подготовки-зависимостей.1', 'готова': True,
                    'квитанция': str(квитанция), 'зависимости': итог['зависимости'],
                    'без_повторных_эффектов': True}
        данные = прежняя or {'схема': 'fum.подготовка-зависимостей.1', 'снимок': снимок,
                    'исполнитель': исполнитель, 'корневая_задача': корневая_задача,
                    'группа_процессов': os.getpgrp(), 'состояния': {запись['путь']: 'не_начата' for запись in инвентарь},
                    'события': [], 'готова': False}
        данные['группа_процессов'] = os.getpgrp()
        for запись in инвентарь:
            путь = запись['путь']
            готовность = проверить_запись(корень, запись)
            if готовность['готова']:
                прежнее_состояние = данные['состояния'][путь]
                данные['состояния'][путь] = 'готова'
                данные['события'].append({'путь': путь, 'фаза': 'автономное_подтверждение',
                    'прежнее_состояние': прежнее_состояние, 'прежний_исход_неизвестен': прежнее_состояние in {'выполняется', 'не_завершена'}})
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
                записать_квитанцию(квитанция, данные)
                continue
            if готовность['состояние'] != 'не_материализована' or данные['состояния'][путь] != 'не_начата':
                raise RuntimeError('попытка не допускает нового init')

            def перед_эффектом(фаза):
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
                данные['состояния'][путь] = 'выполняется'
                данные['события'].append({'путь': путь, 'фаза': фаза, 'группа_процессов': os.getpgrp()})
                записать_квитанцию(квитанция, данные)

            перед_эффектом('намерение')
            try:
                _, ошибки = исходный.initialize_registered_dependency(корень, путь, перед_эффектом=перед_эффектом)
                готовность = проверить_запись(корень, запись)
                if ошибки or not готовность['готова']:
                    raise RuntimeError('; '.join(ошибки) or готовность['состояние'])
                проверить_владение(корень, снимок, исполнитель, корневая_задача)
            except BaseException as ошибка:
                данные['состояния'][путь] = 'не_завершена'
                данные['события'].append({'путь': путь, 'фаза': 'отказ', 'причина': str(ошибка)})
                записать_квитанцию(квитанция, данные)
                raise
            данные['состояния'][путь] = 'готова'
            данные['события'].append({'путь': путь, 'фаза': 'готовность_проверена'})
            записать_квитанцию(квитанция, данные)
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        итог = проверить_зависимости(корень)
        проверить_владение(корень, снимок, исполнитель, корневая_задача)
        if not итог['готова']:
            raise RuntimeError('итоговая готовность не подтверждена')
        данные['готова'] = True
        записать_квитанцию(квитанция, данные)
        return {'схема': 'fum.результат-подготовки-зависимостей.1', 'готова': True,
                'квитанция': str(квитанция), 'зависимости': итог['зависимости'], 'без_повторных_эффектов': False}
    finally:
        os.close(дескриптор)


def выполнить_команду():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('команда', choices=['готовность', 'проверить', 'снимок', 'подготовить', 'возобновить'])
    разбор.add_argument('--корень-репозитория', required=True)
    разбор.add_argument('--путь')
    разбор.add_argument('--ожидаемая-ревизия')
    разбор.add_argument('--снимок')
    разбор.add_argument('--исполнитель')
    разбор.add_argument('--корневая-задача')
    параметры = разбор.parse_args()
    try:
        if параметры.команда == 'готовность':
            if not параметры.путь:
                raise RuntimeError('готовность требует --путь')
            результат = проверить_готовность_зависимости(параметры.корень_репозитория, параметры.путь,
                                                        ожидаемая_ревизия=параметры.ожидаемая_ревизия)
        elif параметры.команда == 'проверить':
            результат = проверить_зависимости(параметры.корень_репозитория)
        elif параметры.команда == 'снимок':
            результат = снять_снимок(параметры.корень_репозитория)
        else:
            if not all((параметры.снимок, параметры.исполнитель, параметры.корневая_задача)):
                raise RuntimeError('подготовка требует снимок и оба UUID')
            if os.getpid() != os.getpgrp():
                os.setsid()
            результат = подготовить_зависимости(параметры.корень_репозитория, прочитать_объект(параметры.снимок),
                параметры.исполнитель, параметры.корневая_задача, возобновить=параметры.команда == 'возобновить')
        print(json.dumps(результат, ensure_ascii=False, sort_keys=True))
        if результат.get('состояние') == 'неизвестность':
            return 2
        return 0 if результат.get('готова', True) else 1
    except ОшибкаДопуска as ошибка:
        print(json.dumps({'схема': 'fum.отказ-подготовки-зависимостей.1', 'готова': False,
                          'состояние': ошибка.состояние, 'причина': str(ошибка)}, ensure_ascii=False))
        return 1
    except (OSError, UnicodeError, RuntimeError, ValueError) as ошибка:
        print(json.dumps({'схема': 'fum.отказ-подготовки-зависимостей.1', 'готова': False,
                          'причина': str(ошибка)}, ensure_ascii=False))
        return 2


if __name__ == '__main__':
    raise SystemExit(выполнить_команду())

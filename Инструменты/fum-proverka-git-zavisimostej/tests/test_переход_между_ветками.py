    def перейти_процессом(сам, снимок, хэш, поколение=None, *, набор=None):
        команда = [sys.executable, '-B', '-c', прежние.ПРОЦЕСС_ПЕРЕХОДА,
            сам.модуль.__file__, 'переход-ветки', '--корень-репозитория', str(сам.корень),
            '--снимок', str(сам.файл_снимка(снимок)), '--исполнитель', сам.исполнитель,
            '--корневая-задача', сам.задача, '--ожидаемый-хэш-квитанции', хэш]
        if поколение is not None:
            команда += ['--предыдущее-поколение', поколение]
        if набор is not None:
            команда += ['--набор-графов', набор['путь'], '--ожидаемый-хэш-набора-графов', набор['хэш_байтов']]
        return subprocess.run(команда, cwd=сам.корень, env=os.environ.copy(),
            start_new_session=True, capture_output=True, text=True, timeout=60)

    def срез(сам):
        итог = {}
        for корень in (сам.корень, сам.квитанция().parent):
            for путь in [корень, *корень.rglob('*')]:
                с = путь.lstat()
                метка = (с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink)
                if stat.S_ISREG(с.st_mode):
                    метка += (с.st_size, с.st_mtime_ns, с.st_ctime_ns, путь.read_bytes())
                elif stat.S_ISLNK(с.st_mode):
                    метка += (os.readlink(путь),)
                итог[str(путь)] = метка
        итог['refs'] = исполнить_гит('for-each-ref', '--format=%(refname) %(objectname)', cwd=сам.корень)
        return итог

    def граница_ветки(сам):
        сам.подготовить_процессом()
        хэш = hashlib.sha256(сам.квитанция().read_bytes()).hexdigest()
        исполнить_гит('switch', '-c', 'codex/следующее-поколение', cwd=сам.корень)
        return сам.модуль.снять_снимок(сам.корень), хэш

    def test_01_новая_ветка_сохраняет_исходную_квитанцию(сам):
        сам.подготовить_процессом()
        путь = сам.квитанция()
        байты, свойства = путь.read_bytes(), путь.stat()
        хэш = hashlib.sha256(байты).hexdigest()
        исполнить_гит('switch', '-c', 'codex/следующий-писатель', cwd=сам.корень)
        снимок = сам.следующая_граница()
        операция = getattr(сам.модуль, 'создать_поколение_ветки', None)
        if операция is None:
            # Реальный прежний маршрут воспроизводит отказ именно при смене ref.
            итог = сам.модуль.начать_новую_попытку(сам.корень, снимок,
                сам.исполнитель, сам.задача, ожидаемый_хэш_квитанции=хэш)
        else:
            итог = операция(сам.корень, снимок, сам.исполнитель, сам.задача,
                предыдущая={'поколение': None, 'sha256': хэш})
        новый = Path(итог['квитанция'])
        сам.assertNotEqual(путь, новый)
        сам.assertEqual('fum.подготовка-зависимостей.4', json.loads(новый.read_bytes())['схема'])
        сам.assertTrue(итог['готова'])
        сам.assertEqual(байты, путь.read_bytes())
        сам.assertEqual((свойства.st_ino, свойства.st_mtime_ns, свойства.st_mode),
            (путь.stat().st_ino, путь.stat().st_mtime_ns, путь.stat().st_mode))

    def test_02_повтор_новым_процессом_не_создаёт_второй_переход(сам):
        снимок, хэш = сам.граница_ветки()
        первый = сам.перейти_процессом(снимок, хэш)
        сам.assertEqual(0, первый.returncode, первый.stderr + первый.stdout)
        данные = json.loads(первый.stdout)
        сам.assertFalse(данные['без_повторных_эффектов'])
        до = сам.срез()
        повтор = сам.перейти_процессом(снимок, хэш)
        сам.assertEqual(0, повтор.returncode, повтор.stderr + повтор.stdout)
        итог = json.loads(повтор.stdout)
        сам.assertTrue(итог.pop('без_повторных_эффектов'))
        данные.pop('без_повторных_эффектов')
        сам.assertEqual(данные, итог)
        сам.assertEqual(до, сам.срез())

    def test_03_расходящиеся_вершины_с_общим_снимком_допустимы(сам):
        сам.подготовить_процессом()
        общий = исполнить_гит('rev-parse', 'HEAD', cwd=сам.корень)
        хэш = hashlib.sha256(сам.квитанция().read_bytes()).hexdigest()
        сам.следующая_граница()
        старый = исполнить_гит('rev-parse', 'HEAD', cwd=сам.корень)
        исполнить_гит('switch', '-c', 'codex/отдельно-принятая-ветка', общий, cwd=сам.корень)
        (сам.корень / 'принято.txt').write_text('Принятые данные другой ветки\n')
        исполнить_гит('add', 'принято.txt', cwd=сам.корень)
        исполнить_гит('commit', '-m', 'Закрепить независимую развилку', cwd=сам.корень)
        новый = исполнить_гит('rev-parse', 'HEAD', cwd=сам.корень)
        сам.assertEqual(1, subprocess.run(['git', '-C', str(сам.корень), 'merge-base',
            '--is-ancestor', старый, новый], capture_output=True).returncode)
        итог = сам.перейти_процессом(сам.модуль.снять_снимок(сам.корень), хэш)
        сам.assertEqual(0, итог.returncode, итог.stderr + итог.stdout)


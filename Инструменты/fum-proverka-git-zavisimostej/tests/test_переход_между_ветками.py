    def test_08_открытый_дескриптор_связан_с_проверенным_адресом(сам):
        источник = сам.фикстура.root / 'проверенный-адрес.json'
        подмена = сам.фикстура.root / 'другой-открытый-файл.json'
        for путь, данные in [(источник, b'{"own":true}'), (подмена, b'{"foreign":true}')]:
            путь.write_bytes(данные); путь.chmod(0o600)
        открыть_путь, открыть_дескриптор = Path.open, os.open

        def адресное_открытие(путь, *аргументы, **параметры):
            return открыть_путь(подмена if Path(путь) == источник else путь, *аргументы, **параметры)

        def адресный_дескриптор(путь, *аргументы, **параметры):
            return открыть_дескриптор(подмена if Path(путь) == источник else путь, *аргументы, **параметры)

        # Инъекция на границе открытия возвращает настоящий FD другого обычного файла.
        with mock.patch.object(Path, 'open', new=адресное_открытие):
            with mock.patch.object(os, 'open', side_effect=адресный_дескриптор):
                with сам.assertRaisesRegex(RuntimeError, 'дескриптор|заменён|измен'):
                    сам.модуль.прочитать_поколение(источник)

    def test_09_глубокая_история_сохраняет_идентичность_между_фазами(сам):
        снимок, хэш = сам.граница_ветки()
        первый = сам.перейти_процессом(снимок, хэш)
        сам.assertEqual(0, первый.returncode, первый.stderr + первый.stdout)
        итог = json.loads(первый.stdout)
        исполнить_гит('switch', '-c', 'codex/проверить-глубокую-историю', cwd=сам.корень)
        снимок = сам.модуль.снять_снимок(сам.корень)
        выбранная = {'поколение': итог['поколение'], 'sha256': итог['sha256']}
        глубокий_архив = сам.квитанция().parent / прежние.КАТАЛОГ_АРХИВА / (хэш + '.json')
        for цель in (сам.квитанция(), глубокий_архив):
            with сам.subTest(источник=цель.name):
                после_подмены = []
                исходный_гит = сам.модуль.исходный.run_git

                def заменить_между_фазами(корень, *аргументы, **параметры):
                    if not после_подмены and аргументы[:2] == ('merge-base', '--is-ancestor'):
                        свойства = цель.stat()
                        подмена = цель.with_name('подмена-глубокой-истории.json')
                        подмена.write_bytes(цель.read_bytes()); подмена.chmod(0o600)
                        os.utime(подмена, ns=(свойства.st_atime_ns, свойства.st_mtime_ns))
                        os.replace(подмена, цель)
                        сам.assertNotEqual(свойства.st_ino, цель.stat().st_ino)
                        после_подмены.append(сам.срез())
                    return исходный_гит(корень, *аргументы, **параметры)

                with mock.patch.object(сам.модуль.исходный, 'run_git', side_effect=заменить_между_фазами):
                    with сам.assertRaisesRegex(RuntimeError, 'цепоч|истори|измен|идентич'):
                        сам.модуль.создать_поколение_ветки(сам.корень, снимок,
                            сам.исполнитель, сам.задача, предыдущая=выбранная)
                сам.assertTrue(после_подмены)
                сам.assertEqual(после_подмены[0], сам.срез())


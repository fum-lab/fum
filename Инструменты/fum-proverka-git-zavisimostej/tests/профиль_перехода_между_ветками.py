def хэш(данные):
    return hashlib.sha256(данные).hexdigest()


def снимок_исходников(корень):
    return {имя: хэш((корень / имя).read_bytes()) for имя in ИСХОДНИКИ}


def приватно_записать(путь, данные):
    сырые = (json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'wb') as поток:
        поток.write(сырые)
        поток.flush()
        os.fsync(поток.fileno())


def рабочий_процесс(файл_входа):
    if not (sys.flags.isolated and sys.flags.no_site and sys.dont_write_bytecode):
        raise RuntimeError('рабочему процессу нужны -I -S -B')
    настройки = json.loads(Path(файл_входа).read_bytes())
    корень_кода = Path(настройки['корень_кода'])
    if снимок_исходников(корень_кода) != настройки['хэши_исходников']:
        raise RuntimeError('состав исходников изменён перед загрузкой')
    описание = importlib.util.spec_from_file_location('измеряемый_производитель',
        корень_кода / ПРОИЗВОДИТЕЛЬ)
    модуль = importlib.util.module_from_spec(описание)
    sys.modules[описание.name] = модуль
    описание.loader.exec_module(модуль)
    os.environ['CODEX_THREAD_ID'] = настройки['нативный_исполнитель']
    события, стек = [], []
    начало_пути = None

    def обернуть(имя, исходная_функция):
        @functools.wraps(исходная_функция)
        def вызвать(*аргументы, **параметры):
            начало = time.perf_counter_ns()
            номер = len(события) + 1
            событие = {'номер': номер, 'родитель': стек[-1] if стек else None,
                'глубина': len(стек), 'стадия': имя,
                'начало_нс': начало - начало_пути, 'конец_нс': None,
                'длительность_нс': None, 'исход': 'выполняется'}
            события.append(событие)
            стек.append(номер)
            try:
                результат = исходная_функция(*аргументы, **параметры)
            except BaseException as ошибка:
                событие.update(исход='отказ', тип_ошибки=type(ошибка).__name__)
                raise
            else:
                событие['исход'] = 'успех'
                return результат
            finally:
                конец = time.perf_counter_ns()
                событие.update(конец_нс=конец - начало_пути,
                    длительность_нс=конец - начало)
                стек.pop()
        return вызвать

    for имя in СТАДИИ:
        setattr(модуль, имя, обернуть(имя, getattr(модуль, имя)))
    исполнитель = (настройки['корневая_задача'] if настройки['сценарий'] == 'чужой_исполнитель'
        else настройки['нативный_исполнитель'])
    исход, ошибка_типа, результат = 'успех', None, None
    начало_пути = time.perf_counter_ns()
    try:
        результат = модуль.создать_поколение_ветки(Path(настройки['корень']),
            настройки['снимок'], исполнитель, настройки['корневая_задача'],
            предыдущая=настройки['предыдущая'])
    except RuntimeError as ошибка:
        if (настройки['сценарий'] != 'чужой_исполнитель'
                or str(ошибка) != 'отсутствующий или чужой native UUID процесса'):
            raise
        исход, ошибка_типа = 'ожидаемый_отказ', type(ошибка).__name__
    finally:
        конец_пути = time.perf_counter_ns()
    if настройки['сценарий'] == 'чужой_исполнитель':
        if исход != 'ожидаемый_отказ':
            raise RuntimeError('чужой исполнитель не получил ожидаемый отказ')
        короткий_результат = None
    else:
        if результат['готова'] is not True:
            raise RuntimeError('успешный полный путь не подтвердил готовность')
        повтор = настройки['сценарий'] == 'повтор'
        if результат['без_повторных_эффектов'] is not повтор:
            raise RuntimeError('полный путь не различил создание и повтор')
        короткий_результат = {п: результат[п] for п in
            ('схема', 'готова', 'поколение', 'sha256', 'без_повторных_эффектов')}
    if стек or any(с['исход'] == 'выполняется' for с in события):
        raise RuntimeError('профиль оставил незавершённые монотонные метки')
    if снимок_исходников(корень_кода) != настройки['хэши_исходников']:
        raise RuntimeError('исходники изменены при выполнении полного пути')
    return {'pid': os.getpid(), 'сценарий': настройки['сценарий'],
        'исход': исход, 'тип_ошибки': ошибка_типа,
        'полный_вызов_нс': конец_пути - начало_пути,
        'события': события, 'результат': короткий_результат}


def срез_файла(путь):
    с = путь.lstat()
    return (с.st_dev, с.st_ino, с.st_mode, с.st_uid, с.st_nlink,
        с.st_size, с.st_mtime_ns, с.st_ctime_ns, путь.read_bytes())


def вызвать_процесс(сценарий, фикстура, корень_кода, снимок, предыдущая,
                     исходники, номер):
    вход = фикстура.фикстура.root / ('профиль-' + str(номер) + '-' + сценарий + '.json')
    приватно_записать(вход, {'сценарий': сценарий, 'корень': str(фикстура.корень),
        'корень_кода': str(корень_кода), 'хэши_исходников': исходники,
        'нативный_исполнитель': фикстура.исполнитель,
        'корневая_задача': фикстура.задача, 'снимок': снимок, 'предыдущая': предыдущая})
    # Вход создаётся до защитного среза и внешнего таймера.
    до = фикстура.срез()
    исходная = фикстура.квитанция()
    исходное_состояние = срез_файла(исходная)
    начало = time.perf_counter_ns()
    процесс = subprocess.run([sys.executable, '-I', '-S', '-B', str(Path(__file__).resolve()),
        '--рабочий-вход', str(вход)], cwd=фикстура.корень, start_new_session=True,
        capture_output=True, text=True, timeout=120)
    внешнее_время = time.perf_counter_ns() - начало
    if процесс.returncode:
        raise RuntimeError('отказ отдельного профилируемого процесса: ' + сценарий)
    ответ = json.loads(процесс.stdout)
    if ответ['сценарий'] != сценарий or ответ['pid'] == os.getpid():
        raise RuntimeError('не подтверждён отдельный рабочий процесс')
    if исходное_состояние != срез_файла(исходная):
        raise RuntimeError('профилируемый путь изменил исходную квитанцию')
    if сценарий in {'повтор', 'чужой_исполнитель'} and фикстура.срез() != до:
        raise RuntimeError('читающий повтор или отказ изменил защищённый срез')
    ответ.update(полный_процесс_нс=внешнее_время,
        исходная_квитанция_сохранена=True,
        срез_неизменен=(True if сценарий in {'повтор', 'чужой_исполнитель'} else None))
    return ответ


def измерить(повторов):
    корень_кода = Path(__file__).resolve().parents[3]
    исходники = снимок_исходников(корень_кода)
    # Импорт и конструктор фикстуры исполняются только родителем, вне всех таймеров.
    sys.path.insert(0, str(корень_кода / ПРЕФИКС / 'tests'))
    from test_переход_между_ветками import ПроверкиПереходаМеждуВетками
    from test_proveritj_git_zavisimostj import run_git as исполнить_гит
    образцы = []
    for номер in range(повторов):
        фикстура = ПроверкиПереходаМеждуВетками('runTest')
        try:
            фикстура.setUp()
            фикстура.подготовить_процессом()
            исходные_байты = фикстура.квитанция().read_bytes()
            исполнить_гит('switch', '-c', 'codex/профиль-перехода', cwd=фикстура.корень)
            снимок = фикстура.модуль.снять_снимок(фикстура.корень)
            предыдущая = {'поколение': None, 'sha256': хэш(исходные_байты)}
            процессы = [вызвать_процесс(с, фикстура, корень_кода, снимок,
                предыдущая, исходники, номер) for с in
                ('создание', 'повтор', 'чужой_исполнитель')]
            if len({п['pid'] for п in процессы}) != 3:
                raise RuntimeError('создание, повтор и отказ не различены процессами')
            if процессы[0]['результат']['поколение'] != процессы[1]['результат']['поколение']:
                raise RuntimeError('повтор вернул другое поколение')
            if процессы[0]['результат']['sha256'] != процессы[1]['результат']['sha256']:
                raise RuntimeError('повтор вернул другие байты результата')
            каталог = фикстура.квитанция().parent / 'fum-подготовка-зависимостей-v4'
            if len(list(каталог.glob('*.json'))) != 1:
                raise RuntimeError('создано не единственное поколение перехода')
            if фикстура.квитанция().read_bytes() != исходные_байты:
                raise RuntimeError('исходная квитанция не сохранилась после всей серии')
            образцы.append({'номер': номер + 1, 'процессы': процессы,
                'число_поколений': 1})
        finally:
            фикстура.doCleanups()
    if снимок_исходников(корень_кода) != исходники:
        raise RuntimeError('состав исходников изменён за полную серию')
    return {'схема': 'fum.профиль-перехода-между-ветками.1', 'повторов': повторов,
        'хэши_исходников': исходники, 'образцы': образцы,
        'медианы_нс': {сценарий: {поле: int(statistics.median(
            п[поле] for о in образцы for п in о['процессы'] if п['сценарий'] == сценарий))
            for поле in ('полный_вызов_нс', 'полный_процесс_нс')}
            for сценарий in ('создание', 'повтор', 'чужой_исполнитель')},
        'границы': {'полный_вызов': 'Один вызов публичного API с монотонными обёртками; '
            'каждая обёртка вызывает исходную функцию ровно один раз и сохраняет исходную ошибку.',
            'полный_процесс': 'Свежий -I -S -B процесс: запуск, входной JSON, проверка хэшей, '
                'загрузка производителя и валидатора, обёртки, полный API, сериализация ответа и выход.',
            'вне_таймеров': 'Импорт и создание временной Git-фикстуры, отдельная исходная подготовка, '
                'переключение ref, снимок, запись входа, защитные срезы, сравнения и итоговый JSON.',
            'вложенность': 'Метки содержат родителя и глубину. Длительности вложенных интервалов '
                'не складываются друг с другом или с полным временем процесса.',
            'кэш_ОС_очищен': False, 'производительность_реального_узла_измерена': False},
        'решение_об_оптимизации': 'Профиль предоставляет измерения для явного решения об оптимизации; '
            'ускорение не заявлено и проверки не ослаблены.',
        'среда': {'python': sys.version, 'платформа': sys.platform}}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--повторы', type=int, default=3)
    разбор.add_argument('--выход', type=Path)
    разбор.add_argument('--рабочий-вход', type=Path)
    параметры = разбор.parse_args()
    if параметры.рабочий_вход is not None:
        print(json.dumps(рабочий_процесс(параметры.рабочий_вход), ensure_ascii=False))
        return 0
    if параметры.повторы < 1 or параметры.выход is None:
        разбор.error('нужны положительное число повторов и новый выход JSON')
    выход = параметры.выход
    if (not выход.is_absolute() or выход.resolve() != выход
            or any(os.path.lexists(п / '.git') for п in выход.parents)
            or any(п.is_symlink() for п in (выход, *выход.parents))):
        разбор.error('нужен новый физический приватный выход вне Git')
    результат = измерить(параметры.повторы)
    приватно_записать(выход, результат)
    print(json.dumps({'повторов': результат['повторов'], 'медианы_нс': результат['медианы_нс'],
        'схема': результат['схема']}, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(главная())

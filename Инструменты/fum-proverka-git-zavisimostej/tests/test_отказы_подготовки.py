"""Ранние отказы наблюдаются на настоящих Git-копиях без внешней сети."""
import fcntl
import json
from pathlib import Path
import unittest
from unittest import mock

import test_подготовка_зависимостей as подготовка
from test_proveritj_git_zavisimostj import run_git


class ПроверкиОтказов(unittest.TestCase):
    setUp = подготовка.ПроверкиОбщейПодготовки.setUp

    def подготовить(сам):
        снимок = сам.модуль.снять_снимок(сам.корень)
        итог = сам.модуль.подготовить_зависимости(сам.корень, снимок, сам.исполнитель, сам.задача)
        return снимок, Path(итог['квитанция'])

    def второй_путь(сам):
        путь = 'Зависимости/Вторая'
        раздел = 'submodule.' + путь
        for поле, значение in [('path', путь), ('url', str(сам.фикстура.fork)),
                              ('fumUpstream', str(сам.фикстура.upstream))]:
            run_git('config', '-f', '.gitmodules', раздел + '.' + поле, значение, cwd=сам.корень)
        run_git('add', '.gitmodules', cwd=сам.корень)
        run_git('update-index', '--add', '--cacheinfo',
                '160000,' + сам.фикстура.first_revision + ',' + путь, cwd=сам.корень)
        return путь, раздел

    def проверить_отказ_до_эффектов(сам):
        снимок = сам.модуль.снять_снимок(сам.корень)
        каталог = Path(run_git('rev-parse', '--absolute-git-dir', cwd=сам.корень))
        до = set(каталог.iterdir())
        with mock.patch.object(сам.модуль.исходный, 'initialize_registered_dependency',
                               side_effect=AssertionError('инициализация до полного допуска')):
            with сам.assertRaises(RuntimeError):
                сам.модуль.подготовить_зависимости(сам.корень, снимок, сам.исполнитель, сам.задача)
        сам.assertEqual(до, set(каталог.iterdir()))

    def test_готовый_повтор_уважает_занятую_блокировку(сам):
        снимок, квитанция = сам.подготовить()
        with квитанция.with_suffix('.lock').open('r+') as замок:
            fcntl.flock(замок, fcntl.LOCK_EX | fcntl.LOCK_NB)
            with сам.assertRaises(RuntimeError):
                сам.модуль.подготовить_зависимости(сам.корень, снимок, сам.исполнитель, сам.задача)

    def test_готовый_повтор_сверяет_снимок_после_чтения(сам):
        снимок, _ = сам.подготовить()
        прежний = сам.модуль.проверить_запись
        изменён = False

        def сдвинуть_после_чтения(*аргументы, **параметры):
            nonlocal изменён
            итог = прежний(*аргументы, **параметры)
            if not изменён:
                изменён = True
                (сам.корень / 'сдвиг.txt').write_text('Индекс изменился\n', encoding='utf-8')
                run_git('add', 'сдвиг.txt', cwd=сам.корень)
            return итог

        with mock.patch.object(сам.модуль, 'проверить_запись', side_effect=сдвинуть_после_чтения):
            with сам.assertRaises(RuntimeError):
                сам.модуль.подготовить_зависимости(сам.корень, снимок, сам.исполнитель, сам.задача)

    def test_локальный_адрес_второй_записи_проверяется_сразу(сам):
        _, раздел = сам.второй_путь()
        run_git('config', раздел + '.url', '/неверный/форк.git', cwd=сам.корень)
        сам.проверить_отказ_до_эффектов()

    def test_неизвестное_состояние_квитанции_сохраняет_отказ(сам):
        снимок, квитанция = сам.подготовить()
        данные = json.loads(квитанция.read_text())
        данные['состояния'][сам.фикстура.path] = 'несуществующее'
        данные['готова'] = False
        квитанция.write_text(json.dumps(данные, ensure_ascii=False), encoding='utf-8')
        до = квитанция.read_bytes()
        with сам.assertRaises(RuntimeError):
            сам.модуль.подготовить_зависимости(сам.корень, снимок, сам.исполнитель, сам.задача)
        сам.assertEqual(до, квитанция.read_bytes())

    def test_файл_вместо_родителя_гит_каталога_отклоняется_сразу(сам):
        сам.второй_путь()
        каталог = Path(run_git('rev-parse', '--absolute-git-dir', cwd=сам.корень))
        (каталог / 'modules').mkdir()
        (каталог / 'modules' / 'Зависимости').write_text('Занятый путь\n', encoding='utf-8')
        сам.проверить_отказ_до_эффектов()

    def test_секция_без_пути_не_выпадает_из_инвентаря(сам):
        run_git('config', '-f', '.gitmodules', 'submodule.лишняя.url',
                str(сам.фикстура.fork), cwd=сам.корень)
        run_git('add', '.gitmodules', cwd=сам.корень)
        сам.проверить_отказ_до_эффектов()

    def test_сбой_чтения_не_становится_доказанной_неполнотой(сам):
        сам.подготовить()
        прежний = сам.модуль.исходный.run_git
        зависимость = сам.корень / сам.фикстура.path

        def отказать_одному_чтению(корень, *аргументы, **параметры):
            if корень == зависимость and аргументы[:2] == ('config', '--get-regexp'):
                raise RuntimeError('Наблюдённый отказ чтения')
            return прежний(корень, *аргументы, **параметры)

        with mock.patch.object(сам.модуль.исходный, 'run_git', side_effect=отказать_одному_чтению):
            итог = сам.модуль.проверить_готовность_зависимости(сам.корень, сам.фикстура.path)
        сам.assertEqual('неизвестность', итог['состояние'])

    def test_подмена_набора_в_последнем_снимке_add_закрывает_готовый_повтор(сам):
        сам.успешная_подготовка(новая=True)
        фикстура = сам.фикстура
        фикстура.выбрать_плоское_добавление()
        сам.assertEqual([], фикстура.добавить())
        настоящий = автоматизация.снять_защищённое_состояние
        настоящая_проверка = автоматизация.ДопускДобавления.проверить
        последний_гейт = False
        внедрений = 0
        def проверка(допуск, *аргументы, **параметры):
            nonlocal последний_гейт
            последний_гейт = параметры.get('результат') is True
            try:
                return настоящая_проверка(допуск, *аргументы, **параметры)
            finally:
                последний_гейт = False
        def подменить(*аргументы, **параметры):
            nonlocal внедрений
            итог = настоящий(*аргументы, **параметры)
            if последний_гейт and внедрений == 0:
                файл = Path(фикстура.набор['путь']); файл.write_bytes(файл.read_bytes() + b' ')
                внедрений += 1
            return итог
        счётчики = (фикстура.клонирования, фикстура.получения)
        до = фикстура.прежние_байты()
        квитанция = фикстура.квитанция.read_bytes()
        with mock.patch.object(автоматизация.ДопускДобавления, 'проверить', new=проверка), \
                mock.patch.object(автоматизация, 'снять_защищённое_состояние', side_effect=подменить):
            ошибки = фикстура.добавить()
        сам.assertEqual(1, внедрений)
        сам.assertTrue(ошибки)
        сам.assertIn('сырые байты входа', '; '.join(ошибки))
        сам.assertEqual(счётчики, (фикстура.клонирования, фикстура.получения))
        сам.assertEqual(квитанция, фикстура.квитанция.read_bytes())
        сам.assertEqual(до, фикстура.прежние_байты())


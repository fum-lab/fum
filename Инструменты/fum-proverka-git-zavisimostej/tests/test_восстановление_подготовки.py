        сам.assertEqual(счётчики, (сам.фикстура.клонирования, сам.фикстура.получения))
        сам.assertEqual(до, сам.фикстура.прежние_байты())
        сам.успешная_подготовка(новая=True)
        сам.успешная_подготовка()

        сам.assertFalse(прежняя['готова'])
        сам.assertEqual('выполняется', прежняя['состояния'][сам.фикстура.path])
        сам.assertEqual(['намерение', 'материализация'], [запись['фаза'] for запись in прежняя['события']])

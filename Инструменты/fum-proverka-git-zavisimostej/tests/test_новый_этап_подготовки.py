    def test_06_замок_и_сдвиг_снимка_закрывают_переход(сам):
        сам.подготовить_процессом(); снимок = сам.следующая_граница()
        with сам.квитанция().with_suffix('.lock').open('r+') as замок:
            fcntl.flock(замок, fcntl.LOCK_EX | fcntl.LOCK_NB)
            сам.проверить_отказ(снимок)
        прежний = сам.модуль.проверить_запись; изменён = False
        def сдвинуть(*аргументы, **параметры):
            nonlocal изменён
            итог = прежний(*аргументы, **параметры)
            if not изменён:
                изменён = True
                (сам.корень / 'сдвиг.txt').write_text('Сдвиг\n')
                исполнить_гит_фикстуры('add', 'сдвиг.txt', cwd=сам.корень)
            return итог
        with mock.patch.object(сам.модуль, 'проверить_запись', side_effect=сдвинуть):
            сам.проверить_отказ(снимок)
        снимок = сам.модуль.снять_снимок(сам.корень)
        до = сам.квитанция().read_bytes(); хэш = hashlib.sha256(до).hexdigest()
        настоящий = сам.модуль.сохранить_архив
        def подменить(*аргументы, **параметры):
            итог = настоящий(*аргументы, **параметры)
            сам.квитанция().write_bytes(до + b' ')
            return итог
        with mock.patch.object(сам.модуль, 'сохранить_архив', side_effect=подменить):
            with сам.assertRaises(RuntimeError): сам.вызвать_переход(снимок, хэш)
        сам.assertEqual(до + b' ', сам.квитанция().read_bytes())
        сам.assertEqual(до, сам.архив(хэш).read_bytes())
        сам.assertEqual(снимок, сам.модуль.снять_снимок(сам.корень))


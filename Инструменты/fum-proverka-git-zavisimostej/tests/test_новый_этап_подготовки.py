class ПроверкиНовогоЭтапа(unittest.TestCase):
    def setUp(сам):
        подготовка.ПроверкиОбщейПодготовки.setUp(сам)
        исполнить_гит_фикстуры('config', 'user.name', 'Открытая фикстура', cwd=сам.корень)
        исполнить_гит_фикстуры('config', 'user.email', 'fixture@example.invalid', cwd=сам.корень)

    def файл_снимка(сам, снимок):
        путь = сам.фикстура.root / 'снимок-этапа.json'
        путь.write_text(json.dumps(снимок, ensure_ascii=False), encoding='utf-8')
        return путь

    def подготовить_процессом(сам, *, режим='готовая', ждать=True):
        снимок = сам.модуль.снять_снимок(сам.корень)
        журнал = сам.фикстура.root / 'вызовы-init.jsonl'
        команда = [sys.executable, '-B', '-c', ПРОЦЕСС_ПОДГОТОВКИ,
                   сам.модуль.__file__, str(сам.корень), str(сам.файл_снимка(снимок)),
                   сам.исполнитель, сам.задача, режим, str(журнал)]
        if not ждать:
            процесс = subprocess.Popen(команда, cwd=сам.корень, env=os.environ.copy(),
                start_new_session=True, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                stderr=subprocess.PIPE, text=True)
            сам.addCleanup(сам.остановить_процесс, процесс)
            сам.assertTrue(json.loads(процесс.stdout.readline())['готова'])
            return снимок, процесс
        итог = subprocess.run(команда, cwd=сам.корень, env=os.environ.copy(),
            start_new_session=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True, timeout=60)
        сам.assertEqual({'готовая': 0, 'частичная': 74, 'неизвестная': 73}[режим],
                        итог.returncode, итог.stderr)
        if режим == 'готовая':
            сам.assertTrue(json.loads(итог.stdout)['готова'])
        return снимок, итог

    def остановить_процесс(сам, процесс):
        if процесс.poll() is None:
            процесс.terminate()
        процесс.communicate(timeout=10)

    def квитанция(сам):
        return Path(исполнить_гит_фикстуры('rev-parse', '--absolute-git-dir', cwd=сам.корень)) / 'fum-подготовка-зависимостей-v1.json'

    def следующая_граница(сам):
        файл = сам.корень / 'этап.txt'
        файл.write_text(файл.read_text() + 'Следующий этап\n' if файл.exists()
                       else 'Следующий этап\n', encoding='utf-8')
        исполнить_гит_фикстуры('add', 'этап.txt', cwd=сам.корень)
        исполнить_гит_фикстуры('commit', '-m', 'Следующий этап фикстуры', cwd=сам.корень)
        return сам.модуль.снять_снимок(сам.корень)

    def вызвать_переход(сам, снимок, хэш=None, **параметры):
        операция = getattr(сам.модуль, 'начать_новую_попытку', None)
        сам.assertTrue(callable(операция), 'Операция явного перехода отсутствует')
        return операция(сам.корень, снимок,
            параметры.get('исполнитель', сам.исполнитель), параметры.get('задача', сам.задача),
            ожидаемый_хэш_квитанции=хэш or hashlib.sha256(сам.квитанция().read_bytes()).hexdigest())

    def перейти_через_команду(сам, снимок, хэш):
        return subprocess.run([sys.executable, '-B', '-c', ПРОЦЕСС_ПЕРЕХОДА, сам.модуль.__file__, 'новая-попытка',
            '--корень-репозитория', str(сам.корень), '--снимок', str(сам.файл_снимка(снимок)),
            '--исполнитель', сам.исполнитель, '--корневая-задача', сам.задача,
            '--ожидаемый-хэш-квитанции', хэш], cwd=сам.корень, env=os.environ.copy(),
            start_new_session=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True, timeout=60)

    def архив(сам, хэш):
        return сам.квитанция().parent / КАТАЛОГ_АРХИВА / (хэш + '.json')

    def проверить_отказ(сам, снимок, *, хэш=None, **параметры):
        до = сам.квитанция().read_bytes()
        with mock.patch.object(сам.модуль.исходный, 'initialize_registered_dependency',
                               side_effect=AssertionError('Эффект до допуска')):
            with сам.assertRaises((RuntimeError, OSError)):
                сам.вызвать_переход(снимок, хэш, **параметры)
        сам.assertEqual(до, сам.квитанция().read_bytes())

    def test_01_закрытый_этап_команда_новый_снимок_и_повтор(сам):
        сам.подготовить_процессом()
        до = сам.квитанция().read_bytes(); хэш = hashlib.sha256(до).hexdigest()
        снимок = сам.следующая_граница()
        исход = сам.перейти_через_команду(снимок, хэш)
        сам.assertEqual(0, исход.returncode, исход.stderr + исход.stdout)
        сам.assertEqual('', исход.stderr)
        сам.assertTrue(json.loads(исход.stdout)['попытка_создана'])
        данные = json.loads(сам.квитанция().read_bytes())
        сам.assertEqual('fum.подготовка-зависимостей.2', данные['схема'])
        сам.assertEqual({'sha256': хэш}, данные['предыдущая_квитанция'])
        сам.assertEqual(до, сам.архив(хэш).read_bytes())
        сам.assertEqual(снимок, данные['снимок'])
        сам.assertEqual('готова', данные['состояния'][сам.фикстура.path])
        журнал = (сам.фикстура.root / 'вызовы-init.jsonl').read_bytes()
        сам.подготовить_процессом(); сам.подготовить_процессом()
        сам.assertEqual(журнал, (сам.фикстура.root / 'вызовы-init.jsonl').read_bytes())
        сам.assertEqual(снимок, сам.модуль.снять_снимок(сам.корень))


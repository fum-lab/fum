#!/usr/bin/env python3
"""Монотонный профиль графа, явной материализации и готового повтора."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import statistics
import tempfile
import time
import platform
import subprocess

from test_допуск_добавления import ФикстураВложеннойТопологии


def измерить(действие):
    начало = time.perf_counter_ns()
    итог = действие()
    return time.perf_counter_ns() - начало, итог


def профиль_сохранения_графов(выход):
    from test_восстановление_подготовки import ФикстураСохраненияГрафов
    измерения = []
    with tempfile.TemporaryDirectory(prefix='fum-preserved-profile-') as временный:
        корень = Path(временный).resolve()
        for номер in range(3):
            фикстура = ФикстураСохраненияГрафов(корень / str(номер))
            процесс, данные = фикстура.подготовить(новая=True)
            if процесс.returncode or not данные['итог']['готова']:
                raise RuntimeError(str(данные))
            до = фикстура.прежние_байты()
            счётчики = (фикстура.клонирования, фикстура.получения)
            инициализаций = 0
            def запретить_инициализацию(*аргументы, **параметры):
                nonlocal инициализаций
                инициализаций += 1
                raise RuntimeError('читающая готовность вызвала init')
            фикстура.модуль.исходный.initialize_registered_dependency = запретить_инициализацию
            графы = фикстура.модуль.прочитать_набор_графов(фикстура.набор)
            порядок = ['карта', 'набор'] if номер % 2 == 0 else ['набор', 'карта']
            пара = {}; результаты = {}
            for вид in порядок:
                параметры = {'графы': графы} if вид == 'карта' else {'набор_графов': фикстура.набор}
                пара[вид], результаты[вид] = измерить(lambda: фикстура.модуль.проверить_зависимости(
                    фикстура.собственный, **параметры))
            if результаты['карта'] != результаты['набор'] or not результаты['набор']['готова']:
                raise RuntimeError('парные результаты готовности различаются')
            готовность_эффекты = {'инициализации': инициализаций,
                'клонирования': фикстура.клонирования - счётчики[0],
                'получения': фикстура.получения - счётчики[1]}
            if any(готовность_эффекты.values()):
                raise RuntimeError('чтение имеет clone/fetch')
            фикстура.выбрать_плоское_добавление()
            ошибки = фикстура.добавить()
            if ошибки: raise RuntimeError(str(ошибки))
            счётчики = (фикстура.клонирования, фикстура.получения)
            повтор_добавления_нс, ошибки = измерить(фикстура.добавить)
            if ошибки or счётчики != (фикстура.клонирования, фикстура.получения):
                raise RuntimeError('готовый add имеет отказ или clone/fetch')
            процесс, данные = фикстура.подготовить(новая=True)
            if процесс.returncode or not данные['итог']['готова']:
                raise RuntimeError(str(данные))
            повтор_подготовки_нс, результат = измерить(фикстура.подготовить)
            процесс, данные = результат
            нулевые = {'инициализации': 0, 'клонирования': 0, 'получения': 0}
            if процесс.returncode or not данные['итог']['готова'] or данные['эффекты'] != нулевые:
                raise RuntimeError('готовая подготовка имеет отказ или эффекты')
            if до != фикстура.прежние_байты():
                raise RuntimeError('старый граф или чужие байты изменились')
            измерения.append({'порядок': порядок, 'карта_нс': пара['карта'], 'набор_нс': пара['набор'],
                'повтор_добавления_нс': повтор_добавления_нс,
                'повтор_подготовки_нс': повтор_подготовки_нс,
                'готовность_эффекты': готовность_эффекты,
                'результаты_совпали': True, 'защита_совпала': True,
                'повторные_эффекты': нулевые})
        исходники = {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest()
            for путь in (Path(фикстура.модуль.__file__), Path(фикстура.модуль.исходный.__file__),
                Path(__file__), Path(__file__).with_name('test_восстановление_подготовки.py'),
                Path(__file__).with_name('test_допуск_добавления.py'),
                Path(__file__).with_name('test_proveritj_git_zavisimostj.py'),
                Path(__file__).with_name('test_подготовка_зависимостей.py'))}
    данные = {'схема': 'fum.профиль-сохранения-графов.1', 'отпечатки_исходников': исходники,
        'таймер': 'perf_counter_ns', 'измерения': измерения,
        'среда': {'версия_интерпретатора': platform.python_version(),
            'версия_гит': subprocess.run(['git', '--version'], check=True,
                stdout=subprocess.PIPE, text=True).stdout.strip()},
        'сценарий': {'свежих_фикстур': 3, 'гитлинков_родителя': 4,
            'выбранных_листьев': 1, 'чужих_деревьев': 2},
        'медианы_нс': {ключ: int(statistics.median(строка[ключ] for строка in измерения))
            for ключ in ('карта_нс', 'набор_нс', 'повтор_добавления_нс', 'повтор_подготовки_нс')},
        'граница': 'Парное сравнение полного S-ready текущего кода: уже разобранная карта '
            'против закреплённого набора; порядок AB/BA/AB. Историческая скорость не измеряется. '
            'Готовый add измеряет весь публичный API. Готовая подготовка включает запуск '
            'отдельного интерпретатора, загрузку кода, снимок, запись входа и весь API. Создание фикстур, '
            'первый add, переходы S, разбор карты перед парой и запись результата исключены. '
            'Кэш ОС не очищен. Проверены старые рабочие/admin-байты и чужие области.',
        'решение_об_оптимизации': 'Полные независимые проверки сохраняются; причинного '
            'ускорения относительно прежней неподдерживаемой операции этот профиль не доказывает.'}
    путь = Path(выход).absolute()
    if путь.resolve() != путь: raise RuntimeError('выход должен иметь физический путь')
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'w') as файл:
        json.dump(данные, файл, ensure_ascii=False, sort_keys=True, indent=2)
        файл.write('\n'); файл.flush(); os.fsync(файл.fileno())
    print(json.dumps({'схема': данные['схема'], 'медианы_нс': данные['медианы_нс'],
        'повторные_эффекты': нулевые}, ensure_ascii=False))


def выполнить():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', required=True)
    разбор.add_argument('--сохранение-графов', action='store_true')
    параметры = разбор.parse_args()
    if параметры.сохранение_графов:
        профиль_сохранения_графов(параметры.выход)
        return
    измерения = []
    with tempfile.TemporaryDirectory(prefix='fum-nested-profile-') as временный:
        корень = Path(временный).resolve()
        for номер in range(3):
            фикстура = ФикстураВложеннойТопологии(корень / str(номер))
            до = фикстура.защищённые_байты()
            граф_нс, _ = измерить(lambda: фикстура.модуль.проверить_дерево_графа(
                фикстура.база.seed, фикстура.описание.revision, фикстура.граф))
            материализация_нс, ошибки = измерить(фикстура.добавить)
            if ошибки: raise RuntimeError(str(ошибки))
            первые = (фикстура.клонирования, фикстура.получения)
            повтор_нс, ошибки = измерить(фикстура.добавить)
            if ошибки: raise RuntimeError(str(ошибки))
            приращения = [фикстура.клонирования - первые[0], фикстура.получения - первые[1]]
            if приращения != [0, 0] or до != фикстура.защищённые_байты():
                raise RuntimeError('повтор имеет эффекты или защищённые байты изменены')
            if фикстура.байты_квитанции != фикстура.квитанция.read_bytes():
                raise RuntimeError('историческая готовая квитанция изменена')
            измерения.append({'граф_нс': граф_нс, 'материализация_нс': материализация_нс,
                'повтор_нс': повтор_нс, 'первичные_клонирования_получения': list(первые),
                'повторные_клонирования_получения': приращения, 'защита_совпала': True})
        исходники = {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest()
            for путь in (Path(фикстура.модуль.__file__), Path(фикстура.модуль.исходный.__file__), Path(__file__),
                         Path(__file__).with_name('test_допуск_добавления.py'),
                         Path(__file__).with_name('test_proveritj_git_zavisimostj.py'),
                         Path(__file__).with_name('test_подготовка_зависимостей.py'))}
    данные = {'схема': 'fum.профиль-вложенной-топологии.1', 'отпечатки_исходников': исходники,
        'таймер': 'perf_counter_ns', 'измерения': измерения,
        'среда': {'версия_интерпретатора': platform.python_version(),
                  'версия_гит': subprocess.run(['git', '--version'], check=True, stdout=subprocess.PIPE, text=True).stdout.strip()},
        'сценарий': {'свежих_фикстур': 3, 'гитлинков_родителя': 4, 'выбранных_листьев': 1,
                      'чужих_деревьев': 2, 'переводы_строк_родителя': 'LF', 'имя_листа': 'deps/try_signal'},
        'медианы_нс': {ключ: int(statistics.median(строка[ключ] for строка in измерения))
            for ключ in ('граф_нс', 'материализация_нс', 'повтор_нс')},
        'граница': 'Три свежие локальные bare-фикстуры. Выбор графа, создание источников/receipt '
                   'и запись результата исключены. Материализация включает весь публичный add, '
                   'предварительный parent clone/fetch, явный parent/leaf и полную защиту. '
                   'Повтор включает весь читающий публичный add. Кэш ОС не очищен.',
        'решение_об_оптимизации': 'Отдельное решение корня записывается в отчёт по измеренным '
                                'медианам; этот профиль не меняет проверяемый алгоритм.'}
    путь = Path(параметры.выход).absolute()
    if путь.resolve() != путь: raise RuntimeError('выход должен иметь физический путь')
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'w') as файл:
        json.dump(данные, файл, ensure_ascii=False, sort_keys=True, indent=2)
        файл.write('\n'); файл.flush(); os.fsync(файл.fileno())
    print(json.dumps({'схема': данные['схема'], 'медианы_нс': данные['медианы_нс'],
                      'повторные_клонирования_получения': [0, 0]}, ensure_ascii=False))


if __name__ == '__main__':
    выполнить()

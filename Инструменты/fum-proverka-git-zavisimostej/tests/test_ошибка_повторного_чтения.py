"""Файловая ошибка старого валидатора сохраняет неизвестность общего допуска."""
from pathlib import Path
import unittest
from unittest import mock

import test_подготовка_зависимостей as подготовка


class ПроверкаПовторногоЧтения(unittest.TestCase):
    setUp = подготовка.ПроверкиОбщейПодготовки.setUp

    def test_повторное_чтение_не_превращает_ошибку_в_несоответствие(сам):
        снимок = сам.модуль.снять_снимок(сам.корень)
        сам.модуль.подготовить_зависимости(сам.корень, снимок, сам.исполнитель, сам.задача)
        настоящий = Path.read_text
        for номер_отказа in (2, 3):
            with сам.subTest(номер_отказа=номер_отказа):
                чтений = 0

                def отказать(путь, *аргументы, **параметры):
                    nonlocal чтений
                    if путь == сам.корень / '.gitmodules':
                        чтений += 1
                        if чтений == номер_отказа:
                            raise PermissionError('Наблюдённый отказ повторного чтения')
                    return настоящий(путь, *аргументы, **параметры)

                with mock.patch.object(Path, 'read_text', autospec=True, side_effect=отказать):
                    итог = сам.модуль.проверить_готовность_зависимости(сам.корень, сам.фикстура.path)
                сам.assertEqual('неизвестность', итог['состояние'])

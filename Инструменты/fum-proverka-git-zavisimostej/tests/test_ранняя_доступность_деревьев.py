def прежняя_автоматизация():
    корень = Path(__file__).resolve().parents[3]
    байты = subprocess.check_output(['git', '--no-optional-locks', '-C', str(корень),
        'show', БАЗА + ':' + ИСХОДНИК])
    модуль = types.ModuleType('прежняя_защита_деревьев')
    модуль.__file__ = str(корень / ИСХОДНИК)
    sys.modules[модуль.__name__] = модуль
    exec(compile(байты, модуль.__file__, 'exec'), модуль.__dict__)
    return модуль, hashlib.sha256(байты).hexdigest()


class ФикстураДеревьев:
    def __init__(сам, каталог, размер=8 * 1024 * 1024):
        сам.каталог = Path(каталог).resolve()
        сам.первичный = сам.каталог / '00-первичный'
        сам.собственный = сам.каталог / '10-собственный'
        сам.доступный = сам.каталог / '20-доступный'
        сам.поздний = сам.каталог / '99-поздний'
        сам.первичный.mkdir()
        сам.гит(сам.первичный, 'init', '-q')
        сам.гит(сам.первичный, 'config', 'user.name', 'FUM Fixture')
        сам.гит(сам.первичный, 'config', 'user.email', 'fixture@example.invalid')
        (сам.первичный / 'README.md').write_text('Исходные байты\n')
        сам.гит(сам.первичный, 'add', 'README.md')
        сам.гит(сам.первичный, 'commit', '-qm', 'Создать фикстуру')
        for номер, дерево in enumerate((сам.собственный, сам.доступный, сам.поздний)):
            сам.гит(сам.первичный, 'worktree', 'add', '-qb', f'codex/дерево-{номер}', str(дерево))
        сам.большой = сам.первичный / 'большой.bin'
        with сам.большой.open('wb') as поток:
            блок = b'FUM\0' * 262144
            for _ in range(размер // len(блок)):
                поток.write(блок)
        (сам.доступный / 'README.md').write_text('Грязные индексные байты\n')
        сам.гит(сам.доступный, 'add', 'README.md')
        (сам.доступный / 'README.md').write_text('Грязные рабочие байты\n')
        сам.общий = сам.первичный / '.git'
        сам.админ = Path(сам.гит(сам.поздний, 'rev-parse', '--absolute-git-dir'))
        сам.ссылка = 'refs/heads/codex/дерево-2'
        (сам.доступный / '.gitignore').write_text('*.cache\n')
        (сам.доступный / 'игнорируемый.cache').write_bytes('Игнорирование не исключает защиту'.encode())
        (сам.доступный / 'неотслеживаемый.txt').write_text('Неотслеживаемые байты\n')

    def гит(сам, корень, *аргументы):
        процесс = subprocess.run(['git', '--no-optional-locks', '-c', 'core.hooksPath=/dev/null',
            '-c', 'core.fsmonitor=false', '-C', str(корень), *аргументы],
            capture_output=True, text=True, timeout=30)
        if процесс.returncode:
            raise RuntimeError(процесс.stderr)
        return процесс.stdout.strip()

    def скрыть_поздний(сам):
        сам.поздний.rename(сам.каталог / 'сохранённый-поздний')

    @contextlib.contextmanager
    def чтения(сам):
        счётчик = {'большой_файл': 0, 'рабочие_файлы': 0, 'прочитано_байтов': 0}
        исходное = Path.open
        рабочие = (сам.первичный, сам.доступный, сам.поздний)

        class УчётЧтения:
            def __init__(учёт, поток, путь):
                учёт.поток, учёт.путь = поток, путь

            def __enter__(учёт):
                учёт.поток.__enter__()
                return учёт

            def __exit__(учёт, *аргументы):
                return учёт.поток.__exit__(*аргументы)

            def __getattr__(учёт, имя):
                return getattr(учёт.поток, имя)

            def read(учёт, *аргументы):
                байты = учёт.поток.read(*аргументы)
                if байты:
                    счётчик['рабочие_файлы'] += 1
                    счётчик['прочитано_байтов'] += len(байты)
                    if учёт.путь == сам.большой:
                        счётчик['большой_файл'] += 1
                return байты

        def открыть(путь, режим='r', *аргументы, **параметры):
            режим = параметры.pop('mode', режим)
            поток = исходное(путь, режим, *аргументы, **параметры)
            if 'r' in режим and 'b' in режим:
                for дерево in рабочие:
                    if путь.is_relative_to(дерево) and '.git' not in путь.relative_to(дерево).parts:
                        return УчётЧтения(поток, путь)
            return поток

        with mock.patch.object(Path, 'open', открыть):
            yield счётчик


class РанняяДоступностьДеревьев(unittest.TestCase):
    def setUp(сам):
        каталог = tempfile.TemporaryDirectory(prefix='fum-ранние-деревья-')
        сам.addCleanup(каталог.cleanup)
        сам.фикстура = ФикстураДеревьев(каталог.name)

    def test_поздний_отказ_до_первого_чтения_большого_файла(сам):
        сам.фикстура.скрыть_поздний()
        with сам.фикстура.чтения() as счётчик:
            with сам.assertRaises(RuntimeError) as отказ:
                автоматизация.снять_защищённое_состояние(сам.фикстура.собственный)
        сам.assertEqual(0, счётчик['большой_файл'])
        сам.assertEqual(0, счётчик['рабочие_файлы'])
        for поле in (str(сам.фикстура.поздний), сам.фикстура.ссылка, str(сам.фикстура.админ), 'отсутствует'):
            сам.assertIn(поле, str(отказ.exception))

    def test_успех_сохраняет_прежний_полный_результат(сам):
        сам.assertEqual('../..\n', (сам.фикстура.админ / 'commondir').read_text())
        прежняя, _ = прежняя_автоматизация()
        ожидаемый = прежняя.снять_защищённое_состояние(сам.фикстура.собственный)
        with сам.фикстура.чтения() as счётчик:
            фактический = автоматизация.снять_защищённое_состояние(сам.фикстура.собственный)
        сам.assertEqual(ожидаемый, фактический)
        сам.assertEqual(8, счётчик['большой_файл'])
        сам.assertGreater(счётчик['рабочие_файлы'], 1)

    def test_указатель_со_скрытой_через_родителя_ссылкой_отказывает_рано(сам):
        for имя in ('.git', 'commondir'):
            with сам.subTest(указатель=имя), tempfile.TemporaryDirectory(prefix='fum-сырые-указатели-') as каталог:
                фикстура = ФикстураДеревьев(каталог)
                перечень = автоматизация.run_git(фикстура.собственный, 'worktree', 'list', '--porcelain')
                внешний = фикстура.каталог / 'внешний' / 'вложенный'
                внешний.mkdir(parents=True)
                прыжок = фикстура.каталог / 'прыжок'
                прыжок.symlink_to(внешний, target_is_directory=True)
                путь = прыжок / '..' / фикстура.первичный.name / '.git'
                if имя == '.git':
                    путь = путь / 'worktrees' / фикстура.админ.name
                    (фикстура.поздний / '.git').write_text('gitdir: ' + str(путь) + '\n')
                else:
                    (фикстура.админ / 'commondir').write_text(str(путь) + '\n')
                настоящий = автоматизация.run_git

                def гит(корень, *аргументы, **параметры):
                    if аргументы == ('worktree', 'list', '--porcelain'):
                        return перечень
                    return настоящий(корень, *аргументы, **параметры)

                with mock.patch.object(автоматизация, 'run_git', гит), фикстура.чтения() as счётчик:
                    with сам.assertRaises(RuntimeError) as отказ:
                        автоматизация.снять_защищённое_состояние(фикстура.собственный)
                сам.assertEqual(0, счётчик['прочитано_байтов'])
                for поле in (str(фикстура.поздний), фикстура.ссылка, str(фикстура.админ)):
                    сам.assertIn(поле, str(отказ.exception))

    def test_отказ_чтения_рабочего_файла_содержит_полный_диагноз(сам):
        настоящий = Path.open
        файл = сам.фикстура.доступный / 'README.md'

        def открыть(путь, *аргументы, **параметры):
            if путь == файл:
                raise PermissionError('синтетический отказ чтения')
            return настоящий(путь, *аргументы, **параметры)

        with mock.patch.object(Path, 'open', открыть), сам.assertRaises(RuntimeError) as отказ:
            автоматизация.снять_защищённое_состояние(сам.фикстура.собственный)
        каталог = сам.фикстура.гит(сам.фикстура.доступный, 'rev-parse', '--absolute-git-dir')
        for поле in (str(сам.фикстура.доступный), 'refs/heads/codex/дерево-1', каталог):
            сам.assertIn(поле, str(отказ.exception))

    def test_скрытая_неполная_admin_регистрация_закрывает_допуск(сам):
        каталог = сам.фикстура.общий / 'worktrees' / 'скрытый-admin'
        скрытый = сам.фикстура.каталог / 'отсутствующий-root'
        настоящий = автоматизация.run_git

        def гит(корень, *аргументы, **параметры):
            ответ = настоящий(корень, *аргументы, **параметры)
            if аргументы == ('worktree', 'list', '--porcelain') and not каталог.exists():
                каталог.mkdir()
                (каталог / 'gitdir').write_text(str(скрытый / '.git') + '\n')
            return ответ

        with mock.patch.object(автоматизация, 'run_git', гит), сам.фикстура.чтения() as счётчик:
            with сам.assertRaises(RuntimeError) as отказ:
                автоматизация.снять_защищённое_состояние(сам.фикстура.собственный)
        сам.assertEqual(0, счётчик['прочитано_байтов'])
        сам.assertIn(str(скрытый), str(отказ.exception))
        сам.assertIn(str(каталог), str(отказ.exception))

    def test_отсутствующий_admin_отказывает_до_рабочих_байтов(сам):
        настоящий = автоматизация.run_git
        подменено = False

        def гит(корень, *аргументы, **параметры):
            nonlocal подменено
            ответ = настоящий(корень, *аргументы, **параметры)
            if аргументы == ('worktree', 'list', '--porcelain') and not подменено:
                подменено = True
                сам.фикстура.админ.rename(сам.фикстура.каталог / 'сохранённый-admin')
            return ответ

        with mock.patch.object(автоматизация, 'run_git', гит), сам.фикстура.чтения() as счётчик:
            with сам.assertRaises(RuntimeError):
                автоматизация.снять_защищённое_состояние(сам.фикстура.собственный)
        сам.assertEqual(0, счётчик['прочитано_байтов'])

    def test_символический_root_закрывает_ранний_допуск(сам):
        сам.фикстура.скрыть_поздний()
        сам.фикстура.поздний.symlink_to(сам.фикстура.каталог / 'сохранённый-поздний', target_is_directory=True)
        with сам.фикстура.чтения() as счётчик:
            with сам.assertRaises(RuntimeError):
                автоматизация.снять_защищённое_состояние(сам.фикстура.собственный)
        сам.assertEqual(0, счётчик['прочитано_байтов'])

    def test_неоднозначная_обратная_регистрация_закрывает_допуск(сам):
        повтор = сам.фикстура.общий / 'worktrees' / 'повтор'
        повтор.mkdir()
        for имя in ('gitdir', 'HEAD', 'commondir'):
            (повтор / имя).write_bytes((сам.фикстура.админ / имя).read_bytes())
        with сам.фикстура.чтения() as счётчик:
            with сам.assertRaises(RuntimeError):
                автоматизация.снять_защищённое_состояние(сам.фикстура.собственный)
        сам.assertEqual(0, счётчик['прочитано_байтов'])

    def test_ошибка_чтения_метаданных_закрывает_допуск(сам):
        исходное = Path.open

        def открыть(путь, *аргументы, **параметры):
            if путь == сам.фикстура.админ / 'gitdir':
                raise PermissionError('Синтетический отказ чтения gitdir')
            return исходное(путь, *аргументы, **параметры)

        with mock.patch.object(Path, 'open', открыть):
            with сам.assertRaises(RuntimeError) as отказ:
                автоматизация.снять_защищённое_состояние(сам.фикстура.собственный)
        сам.assertIn('gitdir', str(отказ.exception))

    def test_подмена_root_маркера_или_admin_при_начале_хэширования(сам):
        исходный_снимок = автоматизация.снимок_защищённого_пути
        for вид in ('root', 'маркер', 'admin'):
            with сам.subTest(вид=вид), tempfile.TemporaryDirectory(prefix='fum-подмена-') as каталог:
                фикстура = ФикстураДеревьев(каталог)
                подменено = False

                def снимок(путь, **параметры):
                    nonlocal подменено
                    if not подменено:
                        подменено = True
                        if вид == 'маркер':
                            маркер = фикстура.поздний / '.git'
                            байты = маркер.read_bytes()
                            маркер.rename(фикстура.каталог / 'прежний-маркер')
                            маркер.write_bytes(байты)
                        else:
                            цель = фикстура.поздний if вид == 'root' else фикстура.админ
                            сохранённый = фикстура.каталог / 'прежняя-область'
                            цель.rename(сохранённый)
                            цель.mkdir()
                            for файл in сохранённый.iterdir():
                                if файл.is_file():
                                    (цель / файл.name).write_bytes(файл.read_bytes())
                    return исходный_снимок(путь, **параметры)

                with mock.patch.object(автоматизация, 'снимок_защищённого_пути', снимок):
                    with сам.assertRaises(RuntimeError):
                        автоматизация.снять_защищённое_состояние(фикстура.собственный)



"""Три открытые фикстуры измеряют читающий допуск и точный готовый повтор."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import statistics
import sys
import tempfile
import time
from unittest import mock

from test_допуск_добавления import ФикстураДопускаДобавления, ИСПОЛНИТЕЛЬ, автоматизация


def выполнить_профиль(выход):
    измерения = []
    for номер in range(1, 4):
        with tempfile.TemporaryDirectory() as временный:
            фикстура = ФикстураДопускаДобавления(Path(временный), разные_имена=True)
            защита = фикстура.защищённые_байты()
            with mock.patch.dict(os.environ, {'CODEX_THREAD_ID': ИСПОЛНИТЕЛЬ}):
                начало = time.perf_counter_ns()
                допуск = автоматизация.ДопускДобавления(фикстура.собственный, фикстура.описание,
                    фикстура.файл_допуска, фикстура.ожидаемый_хэш)
                готовый = допуск.проверить()
                if готовый is not False:
                    raise RuntimeError('исходный допуск должен предшествовать регистрации')
                длительность_допуска = time.perf_counter_ns() - начало
            первый_итог = фикстура.добавить()
            if первый_итог != []:
                raise RuntimeError('первое добавление не прошло: ' + repr(первый_итог))
            счётчики = (фикстура.клонирования, фикстура.получения)
            начало = time.perf_counter_ns()
            ошибки = фикстура.добавить()
            длительность_повтора = time.perf_counter_ns() - начало
            if ошибки != []:
                raise RuntimeError('готовый повтор не прошёл: ' + repr(ошибки))
            if счётчики != (фикстура.клонирования, фикстура.получения):
                raise RuntimeError('готовый повтор клонировал или получил новые данные')
            if защита != фикстура.защищённые_байты():
                raise RuntimeError('защищённые области изменились')
            if фикстура.байты_квитанции != фикстура.квитанция.read_bytes():
                raise RuntimeError('выбранная квитанция изменилась')
            измерения.append({'повтор': номер, 'допуск_наносекунды': длительность_допуска,
                'готовый_повтор_наносекунды': длительность_повтора,
                'новых_клонирований_при_повторе': 0, 'новых_получений_при_повторе': 0,
                'байты_независимого_допуска': фикстура.файл_допуска.stat().st_size,
                'байты_описания_защиты': фикстура.файл_защиты.stat().st_size})
    каталог = Path(__file__).resolve().parent
    пути = [Path(__file__).resolve(), каталог / 'test_допуск_добавления.py',
        каталог / 'test_proveritj_git_zavisimostj.py',
        каталог.parent / 'scripts' / 'proveritj-git-zavisimostj.py',
        каталог.parent / 'scripts' / 'подготовка_зависимостей.py']
    результат = {'схема': 'fum.профиль-допуска-добавления.1', 'версия_python': sys.version,
        'уровень_оптимизации_python': sys.flags.optimize,
        'исходники': {путь.relative_to(каталог.parent).as_posix(): hashlib.sha256(путь.read_bytes()).hexdigest()
                      for путь in пути}, 'измерения': измерения,
        'медиана_допуска_наносекунды': statistics.median(запись['допуск_наносекунды'] for запись in измерения),
        'медиана_готового_повтора_наносекунды': statistics.median(запись['готовый_повтор_наносекунды'] for запись in измерения),
        'границы': {'включены': ['процесс Python', 'чтение входов и их SHA', 'свежая загрузка S',
            'читающие Git-вызовы', 'полный снимок защищённых областей'],
            'исключены': ['подготовка фикстуры и receipt', 'первый clone и fetch', 'сериализация результата'],
            'кэши_операционной_системы_очищались': False,
            'размер': 'Одна новая зависимость, пустой прежний инвентарь, первичный и два чужих дерева; три небольшие локальные bare-фикстуры.'},
        'решение_об_оптимизации': 'Сохранить полные проверки байтов и привязок. Эти измерения не обосновывают кэширование и не характеризуют размер всего FUM. Профиль нового этапа подготовки имеет другие границы и непосредственно не сравнивается.'}
    with Path(выход).open('x', encoding='utf-8') as поток:
        json.dump(результат, поток, ensure_ascii=False, sort_keys=True, indent=2)
        поток.write('\n')
    print(json.dumps({ключ: результат[ключ] for ключ in (
        'медиана_допуска_наносекунды', 'медиана_готового_повтора_наносекунды')}, ensure_ascii=False))


if __name__ == '__main__':
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument('--выход', required=True)
    выполнить_профиль(разборщик.parse_args().выход)

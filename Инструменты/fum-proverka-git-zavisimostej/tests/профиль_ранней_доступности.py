"""Парный открытый профиль успешной защиты и позднего недоступного дерева."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import statistics
import tempfile
import time

from test_ранняя_доступность_деревьев import (
    автоматизация, прежняя_автоматизация, ФикстураДеревьев, БАЗА, ИСХОДНИК,
)


def измерить(модуль, фикстура):
    with фикстура.чтения() as счётчик:
        начало = time.perf_counter_ns()
        try:
            результат = модуль.снять_защищённое_состояние(фикстура.собственный)
            отказ = None
        except RuntimeError as ошибка:
            результат, отказ = None, str(ошибка)
        длительность = time.perf_counter_ns() - начало
    return результат, отказ, {'длительность_наносекунды': длительность, **счётчик}


def главная():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument('--выход', type=Path, required=True)
    разбор.add_argument('--повторы', type=int, default=3)
    разбор.add_argument('--размер-мб', type=int, default=256)
    параметры = разбор.parse_args()
    if параметры.повторы < 1 or параметры.размер_мб < 8:
        разбор.error('нужны положительные повторы и файл не меньше 8 МиБ')
    прежняя, прежний_хэш = прежняя_автоматизация()
    исходники = [Path(автоматизация.__file__), Path(__file__),
        Path(__file__).with_name('test_ранняя_доступность_деревьев.py')]
    до = {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in исходники}
    измерения = []
    with tempfile.TemporaryDirectory(prefix='fum-профиль-ранних-деревьев-') as каталог:
        фикстура = ФикстураДеревьев(каталог, параметры.размер_мб * 1024 * 1024)
        ожидаемый = прежняя.снять_защищённое_состояние(фикстура.собственный)
        for сценарий in ('успех', 'отказ'):
            if сценарий == 'отказ':
                фикстура.скрыть_поздний()
            for повтор in range(параметры.повторы):
                порядок = [('до', прежняя), ('после', автоматизация)]
                if повтор % 2:
                    порядок.reverse()
                for версия, модуль in порядок:
                    результат, отказ, замер = измерить(модуль, фикстура)
                    if сценарий == 'успех':
                        if отказ is not None or результат != ожидаемый:
                            raise RuntimeError('успешный полный результат изменился')
                    elif результат is not None or отказ is None:
                        raise RuntimeError('недоступное дерево не закрыло допуск')
                    elif версия == 'после':
                        if замер['прочитано_байтов'] != 0:
                            raise RuntimeError('новый отказ прочитал рабочие байты')
                        if not all(поле in отказ for поле in
                            (str(фикстура.поздний), фикстура.ссылка, str(фикстура.админ))):
                            raise RuntimeError('новый диагноз неполон')
                    измерения.append({'сценарий': сценарий, 'версия': версия,
                        'повтор': повтор + 1, 'результат': 'полное_совпадение' if отказ is None else 'отказ',
                        **замер})
    после = {путь.name: hashlib.sha256(путь.read_bytes()).hexdigest() for путь in исходники}
    if до != после:
        raise RuntimeError('исходники изменились во время профиля')
    медианы = {сценарий: {версия: statistics.median(замер['длительность_наносекунды']
        for замер in измерения if замер['сценарий'] == сценарий and замер['версия'] == версия)
        for версия in ('до', 'после')} for сценарий in ('успех', 'отказ')}
    итог = {'схема': 'fum.профиль-ранней-доступности.1', 'база': БАЗА,
        'исходник': ИСХОДНИК, 'прежний_sha256': прежний_хэш, 'исходники': до,
        'python': platform.python_version(), 'система': platform.system(),
        'условия': {'деревьев': 4, 'размер_большого_файла': параметры.размер_мб * 1024 * 1024,
            'повторов': параметры.повторы, 'сеть': False,
            'граница': 'Только producer со счётчиком реальных чтений. Создание фикстуры, загрузка кода, прогрев и запись исключены. Один вход; чередование порядка; кэш ОС не очищается.'},
        'измерения': измерения, 'медианы_наносекунды': медианы,
        'полный_результат_сохранён': True, 'отказ_без_рабочих_байтов': True,
        'решение': 'Ранний проход необходим для точного дешёвого отказа; прежнее хэширование сохранено. Цена успешного прохода измеряется отдельно; общий FUM не профилировался.'}
    with параметры.выход.open('x', encoding='utf-8') as поток:
        поток.write(json.dumps(итог, ensure_ascii=False, sort_keys=True, indent=2) + '\n')
    print(json.dumps({'медианы_наносекунды': медианы, 'полный_результат_сохранён': True}, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(главная())

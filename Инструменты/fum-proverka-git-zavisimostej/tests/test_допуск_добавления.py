    def транспорт(сам, каталог, *аргументы, **параметры):
        if 'clone' in аргументы or 'fetch' in аргументы:
            if 'clone' in аргументы:
                адрес = аргументы[-2]
            else:
                номер = аргументы.index('fetch')
                удалённый = next(часть for часть in аргументы[номер + 1:] if часть in ('origin', 'upstream'))
                адрес = сам.настоящий_гит(каталог, *аргументы[:номер], 'config', '--get', 'remote.' + удалённый + '.url').stdout
            if адрес in сам.лист_адреса:
                сам.клонирования += int('clone' in аргументы)
                сам.получения += int('fetch' in аргументы)
                локальный = (сам.зеркало_листа, сам.оригинал_листа)[сам.лист_адреса.index(адрес)]
                return сам.настоящий_гит(каталог, '-c', 'protocol.file.allow=always',
                    '-c', f'url.{локальный}.insteadOf={адрес}', *аргументы, **параметры)
        return super().транспорт(каталог, *аргументы, **параметры)



def хэш(байты):
    return hashlib.sha256(байты).hexdigest()


def записать_объект(путь, данные):
    путь.write_text(json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2) + '\n')
    путь.chmod(0o600)
    return {'путь': str(путь), 'хэш_байтов': хэш(путь.read_bytes())}


def полный_снимок(путь, *, исключить=()):
    """Независимое сравнение включает грязные файлы и административные байты."""
    результат = {}
    for файл in sorted(путь.rglob('*')):
        if файл.relative_to(путь).parts[0] in исключить:
            continue
        свойства = файл.lstat()
        результат[файл.relative_to(путь).as_posix()] = (
            stat.S_IMODE(свойства.st_mode),
            os.readlink(файл) if файл.is_symlink() else файл.read_bytes() if файл.is_file() else None,
        )
    return результат



    def test_символическая_ссылка_компонента_и_остаток_модуля_до_клонирования(сам):
        внешний = сам.фикстура.корень / 'внешний'; внешний.mkdir()
        (сам.фикстура.собственный / 'Зависимости').symlink_to(внешний, target_is_directory=True)
        сам.ранний_отказ()

    def test_поздняя_подмена_источника_останавливает_регистрацию(сам):
        прежний = автоматизация.preflight_dependency
        def подменить(*аргументы, **параметры):
            итог = прежний(*аргументы, **параметры)
            сам.фикстура.файл_допуска.write_bytes(сам.фикстура.файл_допуска.read_bytes() + b' ')
            return итог
        with mock.patch.object(автоматизация, 'preflight_dependency', side_effect=подменить):
            ошибки = сам.фикстура.добавить()
        сам.assertTrue(ошибки)
        сам.assertFalse((сам.фикстура.собственный / '.gitmodules').exists())
        сам.assertFalse((сам.фикстура.собственный / сам.фикстура.описание.path).exists())

    def test_успех_разных_имён_и_повтор_сохраняют_чужие_байты(сам):
        сам.фикстура = ФикстураДопускаДобавления(Path(сам.временный.name) / 'разные', разные_имена=True, общий_модуль=True)
        до = сам.фикстура.защищённые_байты()

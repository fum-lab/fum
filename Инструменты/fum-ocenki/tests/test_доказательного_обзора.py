class ДоказательныйОбзор(unittest.TestCase):
    def setUp(сам):
        сам.пример = основа.СозданиеКоммита()
        сам.пример.setUp()
        сам.addCleanup(сам.пример.doCleanups)
        сам.реестр = сам.пример.корень / обзор.ПУТЬ_РЕЕСТРА
        сам.реестр.parent.mkdir(parents=True)
        сам.реестр.write_text(json.dumps({
            'схема': 'fum.реестр-доказательного-обзора.1',
            'компоненты': [{'имя': 'Синтетические данные', 'файлы': ['данные.txt']}],
            'приёмки': [], 'отказы': [],
        }, ensure_ascii=False))
        сам.пример.параметры['разрешённые_цели'].append(обзор.ПУТЬ_РЕЕСТРА)

    def создать(сам):
        сам.пример.готовить()
        сам.итог = сам.пример.создать()
        сам.подготовка = Path(сам.пример.параметры['подготовка'])
        сам.квитанция = Path(сам.пример.параметры['квитанция'])
        сам.кэш = сам.квитанция.with_name(сам.квитанция.name + '.автообзор')
        return сам.итог

    def применить(сам, **параметры):
        return обзор.применить(сам.подготовка, сам.квитанция, **параметры)

    def test_настоящий_вызов_сам_создаёт_обзор_и_сохраняет_шесть_полей(сам):
        итог = сам.создать()
        сам.assertEqual({'коммит', 'дерево', 'родители', 'автор', 'коммиттер', 'сообщение_sha256'}, set(итог))
        сам.assertTrue(сам.кэш.is_dir())
        повтор = сам.применить()
        сам.assertTrue(повтор['повтор'])
        данные = повтор['обзор']
        сам.assertEqual(итог['коммит'], данные['коммит'])
        сам.assertEqual(итог['дерево'], данные['дерево'])
        сам.assertEqual(итог['родители'], данные['родители'])
        сам.assertEqual('присутствует', данные['компоненты'][0]['состояние'])
        сам.assertEqual(основа.ЗАПУСК, данные['предкоммитные_проверки'][0]['идентификатор'])
        сам.assertEqual('адресная', данные['предкоммитные_проверки'][0]['класс'])
        сам.assertEqual('unknown', данные['неизвестно']['проверки_на_коммите'])
        сам.assertEqual('unknown', данные['неизвестно']['полная_приёмка'])
        сам.assertEqual('unknown', данные['неизвестно']['текущая_доставка'])
        сам.assertEqual('unknown', данные['неизвестно']['обратный_приём'])

    def test_повтор_сохраняет_байты_номер_узла_и_время_изменения_без_нового_коммита(сам):
        сам.создать()
        первый = сам.применить()
        каталог = сам.кэш / первый['ключ']
        снимок = {файл_кэша.name: (файл_кэша.read_bytes(), файл_кэша.stat().st_ino, файл_кэша.stat().st_mtime_ns) for файл_кэша in каталог.iterdir()}
        сам.assertEqual(сам.итог, сам.пример.создать())
        сам.assertEqual(снимок, {файл_кэша.name: (файл_кэша.read_bytes(), файл_кэша.stat().st_ino, файл_кэша.stat().st_mtime_ns) for файл_кэша in каталог.iterdir()})
        сам.assertEqual(сам.итог['коммит'], сам.пример.гит('rev-parse', 'HEAD').strip())
        for файл_кэша in каталог.iterdir():
            сам.assertEqual(0o600, файл_кэша.stat().st_mode & 0o777)
        сам.assertEqual(0o700, каталог.stat().st_mode & 0o777)

    def test_фиксированный_коммит_не_читает_грязное_дерево_и_новую_ветку(сам):
        сам.создать()

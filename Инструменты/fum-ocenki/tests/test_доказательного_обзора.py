    def test_подмена_свидетельства_или_отпечатка_не_даёт_обзор(сам):
        сам.создать()
        исходные = сам.квитанция.read_bytes()
        for поле in ('свидетельства', 'гит', 'содержимое'):
            with сам.subTest(поле=поле):
                запись = json.loads(исходные)
                if поле == 'свидетельства':
                    запись['допуск'][поле][0][1] = '0' * 64
                else:
                    запись['допуск'][поле] = 'sha256:' + '0' * 64
                сам.квитанция.write_text(json.dumps(запись, ensure_ascii=False))
                with сам.assertRaises(обзор.ОшибкаОбзора):
                    сам.применить()

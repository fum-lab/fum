"""Поддержанные обычные подготовки проверяются на настоящих квитанциях."""
import json
import os
from pathlib import Path
import subprocess
import sys
import unittest

ПАКЕТ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ПАКЕТ.parent / 'fum-svyaznostj-rabochej-sessii/tests'))
sys.path.insert(0, str(ПАКЕТ / 'scripts'))
import доказательный_обзор as обзор
import контекст_обзора as контекст
from контракт_обзора import байты, хэш


class ОбычнаяПодготовкаОбзора(unittest.TestCase):
    def создать_пример(self, версия):
        import test_создание_коммита as база
        import test_независимой_контрольной_точки as независимая
        import test_обычной_дочерней_точки as дочерняя
        маска = os.umask(0o022)
        self.addCleanup(os.umask, маска)
        if версия == 11:
            пример = независимая.РеальныйНезависимыйСоздатель()
            self.addCleanup(пример.doCleanups)
            пример.setUp()
            параметры = пример.п
            допуск = {'выбранный_состав': пример.выбранный}
            пример.м.подготовить(параметры, **допуск)
            подготовка = Path(параметры['подготовка'])
            пример.наполнить(json.loads(подготовка.read_bytes()))
            пример.проверить_данные()
            пример.м.объявить_готовность(подготовка, [база.ЗАПУСК], 600, **допуск)
            итог = пример.м.создать(подготовка, [база.ЗАПУСК], **допуск)
            схема = 'fum.создание-коммита.9'
        else:
            пример = дочерняя.ОбычнаяДочерняяТочка()
            self.addCleanup(пример.doCleanups)
            пример.setUp()
            параметры = пример.параметры
            подготовка = Path(параметры['подготовка'])
            пример.готовить()
            итог = пример.создать()
            схема = 'fum.создание-коммита.7'
        данные = json.loads(подготовка.read_bytes())
        self.assertEqual('fum.подготовленный-коммит.' + str(версия), данные['схема'])
        self.assertEqual(схема, данные['параметры']['схема'])
        return подготовка, Path(параметры['квитанция']), Path(параметры['корень']), итог

    def проверить_повтор(self, пример):
        подготовка, квитанция, корень, итог = пример
        поля = {'коммит', 'дерево', 'родители', 'автор', 'коммиттер', 'сообщение_sha256'}
        self.assertEqual(поля, set(итог))
        каталог_кэша = квитанция.with_name(квитанция.name + '.автообзор')
        self.assertTrue(каталог_кэша.is_dir(), 'Первичный Create должен сам сохранить автообзор')
        результат = обзор.применить(подготовка, квитанция, ожидаемый=итог)
        self.assertIs(результат['повтор'], True, 'Create должен завершить первичный автообзор')
        self.assertEqual(итог, {имя: результат['обзор'][имя] for имя in поля})
        каталог = каталог_кэша / результат['ключ']
        def снимок():
            return {п.name: (п.read_bytes(), п.stat().st_ino, п.stat().st_mtime_ns)
                    for п in каталог.iterdir()}
        до, прежняя = снимок(), квитанция.read_bytes()
        процесс = subprocess.run([sys.executable, '-B', str(ПАКЕТ / 'scripts/доказательный-обзор.py'),
            '--подготовка', str(подготовка), '--квитанция', str(квитанция)],
            cwd=корень, capture_output=True, timeout=30)
        self.assertEqual(0, процесс.returncode, процесс.stderr)
        повтор = json.loads(процесс.stdout)
        self.assertIs(повтор['повтор'], True)
        self.assertEqual(результат['ключ'], повтор['ключ'])
        self.assertEqual(результат['обзор'], повтор['обзор'])
        self.assertEqual(до, снимок())
        self.assertEqual(прежняя, квитанция.read_bytes())
        self.assertEqual(итог['коммит'], subprocess.check_output(
            ['git', '-C', str(корень), 'rev-parse', 'HEAD'], text=True).strip())

    def test_ROOT_11_9_обзор_и_свежий_повтор(self):
        пример = self.создать_пример(11)
        self.проверить_повтор(пример)
        подготовка, квитанция, _, итог = пример
        исходная_подготовка, исходная_квитанция = подготовка.read_bytes(), квитанция.read_bytes()
        for запрос in ('Журнал/запрос.md', 'Журнал/этап/вложенный/запрос.md',
                       'Журналы/этап/запрос.md', 'Журнал/этап/отчёт.md',
                       'Журнал//запрос.md'):
            with self.subTest(запрос=запрос):
                п = json.loads(исходная_подготовка)
                п['параметры']['запрос'] = запрос
                подготовка.write_bytes(байты(п))
                к = json.loads(исходная_квитанция)
                к['подготовка_sha256'] = хэш(подготовка.read_bytes())
                квитанция.write_bytes(байты(к))
                with self.assertRaisesRegex(ValueError, 'пара Журнала|относительный путь'):
                    контекст.прочитать(подготовка, квитанция)
        for версия, maker in ((12, 9), (11, 7), (9, 9)):
            with self.subTest(версия=версия, maker=maker):
                п = json.loads(исходная_подготовка)
                п['схема'] = 'fum.подготовленный-коммит.' + str(версия)
                п['параметры']['схема'] = 'fum.создание-коммита.' + str(maker)
                подготовка.write_bytes(байты(п))
                к = json.loads(исходная_квитанция)
                к['подготовка_sha256'] = хэш(подготовка.read_bytes())
                квитанция.write_bytes(байты(к))
                with self.assertRaises(ValueError):
                    контекст.прочитать(подготовка, квитанция)
        подготовка.write_bytes(исходная_подготовка)
        for поле in ('подготовка_sha256', 'свидетельства', 'гит', 'содержимое', 'коммит'):
            к = json.loads(исходная_квитанция)
            if поле == 'подготовка_sha256':
                к[поле] = '0' * 64
            elif поле == 'коммит':
                к['результат'][поле] = '0' * 40
            elif поле == 'свидетельства':
                к['допуск'][поле][0][1] = '0' * 64
            else:
                к['допуск'][поле] = 'sha256:' + '0' * 64
            квитанция.write_bytes(байты(к))
            with self.subTest(поле=поле), self.assertRaises(обзор.ОшибкаОбзора):
                обзор.применить(подготовка, квитанция, ожидаемый=итог)
        квитанция.write_bytes(исходная_квитанция)

    def test_дочерняя_9_7_обзор_и_свежий_повтор(self):
        self.проверить_повтор(self.создать_пример(9))


if __name__ == '__main__':
    unittest.main()

"""Измерить реальный автообзор, его повтор и пакет прямого импорта без сети."""
import argparse
import hashlib
import json
from pathlib import Path
import statistics
import sys
import tempfile
import time
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_доказательного_обзора as сценарий


def измерить_обзор():
    пример = сценарий.ДоказательныйОбзор()
    пример.setUp()
    исходный_обзор = сценарий.обзор.применить
    исходное_чтение = сценарий.обзор.СрезГит.выполнить
    чтения, наблюдения = [], []

    def читать(срез, *аргументы, **параметры):
        начало = time.monotonic_ns()
        результат = исходное_чтение(срез, *аргументы, **параметры)
        чтения.append(time.monotonic_ns() - начало)
        return результат

    def применить(*аргументы, **параметры):
        начало, счётчик = time.monotonic_ns(), len(чтения)
        результат = исходный_обзор(*аргументы, **параметры)
        наблюдения.append({'повтор': результат['повтор'],
            'длительность_нс': time.monotonic_ns() - начало,
            'вызовов_гит': len(чтения) - счётчик,
            'чтение_гит_нс': sum(чтения[счётчик:])})
        return результат

    try:
        пример.пример.готовить()
        with mock.patch.object(сценарий.обзор.СрезГит, 'выполнить', читать), mock.patch.object(сценарий.обзор, 'применить', применить):
            коммит = пример.пример.создать()
            подготовка = Path(пример.пример.параметры['подготовка'])
            квитанция = Path(пример.пример.параметры['квитанция'])
            первый = применить(подготовка, квитанция)
            каталог = квитанция.with_name(квитанция.name + '.автообзор') / первый['ключ']
            снимок = {п.name: (п.read_bytes(), п.stat().st_ino, п.stat().st_mtime_ns) for п in каталог.iterdir()}
            for _ in range(4):
                повтор = применить(подготовка, квитанция)
                assert повтор == первый
            assert снимок == {п.name: (п.read_bytes(), п.stat().st_ino, п.stat().st_mtime_ns) for п in каталог.iterdir()}
            assert коммит['коммит'] == пример.пример.гит('rev-parse', 'HEAD').strip()
        assert len(наблюдения) == 6 and наблюдения[0]['повтор'] is False and all(н['повтор'] for н in наблюдения[1:])
        return {'граница': 'Синтетический малый C: один компонент, одна выбранная проверка, без сети; подготовка коммита исключена.',
            'коммит': коммит['коммит'], 'дерево': коммит['дерево'],
            'первый_автообзор': наблюдения[0], 'повторы': наблюдения[1:],
            'медиана_повтора_нс': statistics.median(н['длительность_нс'] for н in наблюдения[1:])}
    finally:
        пример.doCleanups()


def измерить_импорт():
    инструменты = Path(__file__).resolve().parents[2]
    sys.path.insert(0, str(инструменты / 'fum-perevod-obyyavlenij-koda-na-russkij-yazyik/scripts'))
    import пакет_перевода_python as переводчик
    поставщик = 'def exported(значение): return значение\n'
    потребитель = 'from поставщик import exported\n' + ''.join('результат = exported(1)\n' for _ in range(400))
    with tempfile.TemporaryDirectory() as временный:
        корень = Path(временный)
        файлы = []
        for имя, текст, переводы, связи in (
            ('поставщик.py', поставщик, {'exported': 'проверенный'}, []),
            ('потребитель.py', потребитель, {}, [{'вид': 'импорт', 'владелец': 'поставщик', 'имя': 'exported',
                'новое': 'проверенный', 'количество': 401, 'источник': 'поставщик.py'}]),
        ):
            (корень / имя).write_text(текст)
            файлы.append({'путь': имя, 'хэш': hashlib.sha256(текст.encode()).hexdigest(),
                'переводы': переводы, 'области': None, 'связи': связи, 'передачи': []})
        наблюдения, отпечатки = [], set()
        for _ in range(5):
            стадии = []
            план = переводчик.подготовить(корень, {'схема': 'fum.пакет-перевода-python.1', 'файлы': файлы}, стадии)
            наблюдения.append(стадии)
            отпечатки.add(план[1]['после'])
            assert план[1]['текст'] == потребитель.replace('exported', 'проверенный')
        assert len(отпечатки) == 1 and (корень / 'потребитель.py').read_text() == потребитель
    return {'граница': 'План без записи: один прямой импорт и 400 связанных вызовов; пять повторов одного входа.',
        'вход_sha256': hashlib.sha256(потребитель.encode()).hexdigest(), 'результат_sha256': отпечатки.pop(),
        'исполнитель_sha256': hashlib.sha256(Path(переводчик.__file__).read_bytes()).hexdigest(),
        'повторы': наблюдения}


def главная():
    разборщик = argparse.ArgumentParser(description=__doc__)
    разборщик.add_argument('--выход', required=True, type=Path)
    аргументы = разборщик.parse_args()
    начало = time.monotonic_ns()
    результат = {'схема': 'fum.профиль-доказательного-обзора.1',
        'сценарий_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'версия_python': sys.version.split()[0],
        'обзор': измерить_обзор(), 'перевод_импорта': измерить_импорт()}
    результат['весь_сценарий_нс'] = time.monotonic_ns() - начало
    with аргументы.выход.open('x') as поток:
        json.dump(результат, поток, ensure_ascii=False, indent=2)
        поток.write('\n')
    print(json.dumps({'первый_автообзор_нс': результат['обзор']['первый_автообзор']['длительность_нс'],
        'медиана_повтора_нс': результат['обзор']['медиана_повтора_нс'],
        'весь_сценарий_нс': результат['весь_сценарий_нс']}, ensure_ascii=False))


if __name__ == '__main__':
    главная()

"""Автоматически применяемый доказательный обзор после проверенного локального C."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
from pathlib import Path
import sys

from контракт_обзора import ОшибкаОбзора, байты, физический, поля, требовать, хэш
import контекст_обзора
import реестр_обзора
import свидетельства_обзора
from срез_гит_обзора import СрезГит
from построение_обзора import построить
from хранение_обзора import сохранить

ПУТЬ_РЕЕСТРА = реестр_обзора.ПУТЬ_РЕЕСТРА
СКРИПТЫ = Path(__file__).resolve().parent
МОДУЛИ = ('контракт_обзора.py', 'контекст_обзора.py', 'реестр_обзора.py', 'срез_гит_обзора.py',
    'свидетельства_обзора.py', 'приёмки_обзора.py', 'сигналы_обзора.py', 'построение_обзора.py',
    'формат_обзора.py', 'хранение_обзора.py', 'доказательный_обзор.py')


def метод():
    пути = [(имя, СКРИПТЫ / имя) for имя in МОДУЛИ]
    пути.append(('валидатор-запуска', свидетельства_обзора.ПУТЬ_ВАЛИДАТОРА))
    отпечатки = []
    for имя, путь in пути:
        модуль = свидетельства_обзора.валидатор() if имя == 'валидатор-запуска' else sys.modules[Path(имя).stem]
        требовать(Path(модуль.__file__).resolve() == путь.resolve(), 'Метод загружен из другого дерева')
        текущий = хэш(физический(путь).read_bytes())
        требовать(getattr(модуль, 'КОД_ПРИ_ЗАГРУЗКЕ', None) == текущий, 'Загруженный метод изменился; нужен новый процесс обзора')
        отпечатки.append([имя, текущий])
    return хэш(байты(отпечатки))


def применить(подготовка, квитанция, *, кэш=None, ожидаемый=None):
    try:
        корень, контекст, хэш_контекста = контекст_обзора.прочитать(подготовка, квитанция)
        if ожидаемый is not None:
            требовать(контекст['результат'] == ожидаемый, 'Обзор не соответствует возвращённому результату создателя')
        срез = СрезГит(корень, контекст['результат']['коммит'])
        сведения_коммита = срез.метаданные()
        требовать(сведения_коммита == контекст['результат'], 'Фактический C отличается от квитанции')
        реестр, хэш_реестра = реестр_обзора.прочитать(срез)
        хэш_метода = метод()
        проверки = свидетельства_обзора.выбранные(срез, контекст)
        основание = {'коммит': сведения_коммита['коммит'], 'реестр_sha256': хэш_реестра,
            'метод_sha256': хэш_метода, 'контекст_sha256': хэш_контекста}
        ключ = хэш(байты(основание))
        готовое = None
        def построить_обзор():
            nonlocal готовое
            if готовое is None:
                готовое = построить(срез, сведения_коммита, реестр, хэш_реестра, хэш_метода, хэш_контекста, проверки)
            return готовое
        def проверить_обзор(срез_обзора):
            поля(срез_обзора, ('схема', *контекст_обзора.ПОЛЯ_РЕЗУЛЬТАТА, 'граница', 'реестр_sha256', 'метод_sha256',
                'контекст_sha256', 'компоненты', 'предкоммитные_проверки', 'приёмки', 'сигналы_автоматизации', 'неизвестно'))
            требовать(срез_обзора['схема'] == 'fum.доказательный-обзор.1' and all(срез_обзора[поле] == ожидаемое_значение for поле, ожидаемое_значение in основание.items())
                and all(срез_обзора[поле] == ожидаемое_значение for поле, ожидаемое_значение in сведения_коммита.items()) and срез_обзора['предкоммитные_проверки'] == проверки, 'Кэш относится к другому срезу или допуску')
            требовать(байты(срез_обзора) == байты(построить_обзор()), 'Выводы кэша отличаются от детерминированного построения из C')
        адрес = Path(квитанция)
        место = кэш if кэш is not None else адрес.with_name(адрес.name + '.автообзор')
        return сохранить(место, ключ, построить_обзор, проверить_обзор)
    except (OSError, ValueError, TypeError, KeyError, UnicodeError) as причина:
        raise ОшибкаОбзора(str(причина)) from причина

"""Проверяемая сохранённая промежуточная приёмка; исполнение не повторяется."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
from контракт_обзора import проверить_идентификатор_объекта, относительный, поля, разобрать, требовать, хэш
import re


def прочитать(срез, строка):
    файл = срез.файл(строка['путь'])
    требовать(файл is not None, 'Не найдено решение приёмки')
    объект_файла, сырые = файл
    решение = разобрать(сырые)
    поля(решение, ('схема', 'состояние', 'граница', 'дерево', 'коммит', 'проверяющий', 'свидетельства'))
    требовать(решение['схема'] == 'fum.решение-приёмки-среза.1' and решение['состояние'] == 'принят промежуточный срез', 'Неизвестный тип решения приёмки')
    требовать(type(решение['граница']) is str and 0 < len(решение['граница']) <= 8192 and решение['граница'].strip()
        and not any(ord(символ) < 32 or ord(символ) == 127 for символ in решение['граница']), 'Неверная граница приёмки')
    требовать(type(решение['проверяющий']) is str and re.fullmatch(r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}', решение['проверяющий']), 'Неверный UUID проверяющего')
    принятый_коммит = проверить_идентификатор_объекта(решение['коммит'])
    данные = срез.метаданные(принятый_коммит)
    требовать(данные['дерево'] == проверить_идентификатор_объекта(решение['дерево']) and срез.включает(принятый_коммит), 'Принятый срез не включён в C либо имеет другое дерево')
    требовать(type(решение['свидетельства']) is list and 0 < len(решение['свидетельства']) <= 16, 'Неверный состав оснований решения')
    пути_оснований = set()
    for свидетельство in решение['свидетельства']:
        поля(свидетельство, ('путь', 'sha256'))
        путь_основания = относительный(свидетельство['путь'])
        требовать(путь_основания not in пути_оснований, 'Повтор основания приёмки')
        пути_оснований.add(путь_основания)
        файл_основания = срез.файл(путь_основания)
        требовать(файл_основания is not None and хэш(файл_основания[1]) == свидетельство['sha256'], 'Основание приёмки изменено или отсутствует')
    return {'имя': строка['имя'], 'путь': строка['путь'], 'blob': объект_файла, 'sha256': хэш(сырые),
        'коммит': принятый_коммит, 'дерево': данные['дерево'], 'родители': данные['родители'],
        'состояние': 'сохранённое решение о промежуточной приёмке', 'граница': решение['граница']}

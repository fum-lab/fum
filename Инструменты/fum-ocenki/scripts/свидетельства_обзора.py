def валидатор():
    if 'отчёты_создания_коммита' in sys.modules:
        return sys.modules['отчёты_создания_коммита']
    имя = 'отчёты_доказательного_обзора'
    if имя not in sys.modules:
        спецификация = importlib.util.spec_from_file_location(имя, ПУТЬ_ВАЛИДАТОРА)
        модуль = importlib.util.module_from_spec(спецификация)
        sys.modules[имя] = модуль
        спецификация.loader.exec_module(модуль)
    return sys.modules[имя]


def выбранные(срез, контекст):
    каталог = str(Path(контекст['сессия']).parent / 'материалы/запуски-проверок')
    состав = срез.записи(каталог, рекурсивно=True)
    допуск = dict(контекст['свидетельства'])
    результаты = []
    отчёты = валидатор()
    for выбранный_идентификатор in контекст['проверки']:
        совпадения = [найденный_путь for найденный_путь, режим, тип, объект_файла in состав if re.fullmatch(r'[1-9][0-9]*_' + re.escape(выбранный_идентификатор) + r'\.json', Path(найденный_путь).name)]
        требовать(len(совпадения) == 1, 'Выбранное свидетельство не найдено однозначно в C')
        путь = совпадения[0]
        объект_файла, сырые = срез.файл(путь)
        требовать(хэш(сырые) == допуск[выбранный_идентификатор], 'Сырые байты запуска отличаются от допуска')
        запись = разобрать(сырые)
        try:
            отчёты.проверить_запись(запись, Path(путь).name, контекст['сессия'])
        except отчёты.ОшибкаОтчёта as причина:
            raise ОшибкаОбзора(str(причина)) from причина
        требовать(запись['схема'] == 'fum.test-run.v4' and запись['состояние'] == 'завершён'
            and запись['статус'] == 'успешно' and запись['код_завершения'] == 0, 'Нужен успешный завершённый v4')
        требовать(запись['профиль_проверки']['отпечаток_снимка'] == контекст['гит']
            and запись['отпечаток_содержимого'] == контекст['содержимое'], 'Отпечатки запуска отличаются от допуска')
        результаты.append({'идентификатор': выбранный_идентификатор, 'путь': путь, 'blob': объект_файла, 'sha256': хэш(сырые),
            'класс': запись['профиль_проверки']['класс'], 'длительность_нс': запись['длительность_наносекунды'],
            'основание': 'Успешное предкоммитное свидетельство выбрано допуском создателя и сохранено в C.'})
    return результаты

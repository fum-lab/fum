"""Область наблюдения задаётся реестром, сохранённым в самом Git-срезе."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
from контракт_обзора import относительный, поля, разобрать, требовать, хэш

ПУТЬ_РЕЕСТРА = 'Инструменты/fum-ocenki/реестр-доказательного-обзора.json'


def прочитать(срез):
    файл = срез.файл(ПУТЬ_РЕЕСТРА)
    if файл is None:
        return {'схема': 'fum.реестр-доказательного-обзора.1', 'компоненты': [], 'приёмки': [], 'отказы': []}, None
    _, сырые = файл
    реестр = разобрать(сырые)
    поля(реестр, ('схема', 'компоненты', 'приёмки', 'отказы'))
    требовать(реестр['схема'] == 'fum.реестр-доказательного-обзора.1', 'Неизвестный реестр обзора')
    for раздел in ('компоненты', 'приёмки', 'отказы'):
        требовать(type(реестр[раздел]) is list and len(реестр[раздел]) <= 32, 'Превышен предел реестра')
        имена = set()
        for строка in реестр[раздел]:
            поля(строка, ('имя', 'файлы') if раздел == 'компоненты' else ('имя', 'путь') if раздел == 'приёмки' else ('имя', 'путь', 'доработка'))
            требовать(type(строка['имя']) is str and 0 < len(строка['имя']) <= 160 and строка['имя'] not in имена, 'Неверное или повторное имя')
            имена.add(строка['имя'])
            пути = строка['файлы'] if раздел == 'компоненты' else [строка['путь']]
            требовать(type(пути) is list and 0 < len(пути) <= 16 and len(set(пути)) == len(пути), 'Неверные пути компонента')
            for путь in пути:
                относительный(путь)
            if раздел == 'отказы':
                относительный(строка['доработка'])
    return реестр, хэш(сырые)

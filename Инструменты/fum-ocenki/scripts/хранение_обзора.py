"""Атомарная публикация собственной приватной пары; повреждение не чинится молча."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
import fcntl
import os
from pathlib import Path
import stat
import tempfile
import time

from контракт_обзора import байты, физический, поля, прочитать_приватный, разобрать, требовать, хэш
from формат_обзора import сформировать_разметку


def каталог(путь):
    путь = физический(путь, приватный=True)
    if not os.path.lexists(путь):
        путь.mkdir(mode=0o700)
    сведения_файла = путь.stat()
    требовать(stat.S_ISDIR(сведения_файла.st_mode) and сведения_файла.st_uid == os.getuid() and stat.S_IMODE(сведения_файла.st_mode) == 0o700, 'Нужен собственный приватный каталог кэша')
    return путь


def синхронизировать_каталог(путь):
    дескриптор = os.open(путь, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        os.fsync(дескриптор)
    finally:
        os.close(дескриптор)


def сохранить(корень, ключ, создать, проверить):
    корень = каталог(корень)
    дескриптор = os.open(корень / 'замок', os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    with os.fdopen(дескриптор, 'r+b') as замок:
        сведения_файла = os.fstat(замок.fileno())
        требовать(stat.S_ISREG(сведения_файла.st_mode) and сведения_файла.st_nlink == 1 and сведения_файла.st_uid == os.getuid()
            and stat.S_IMODE(сведения_файла.st_mode) == 0o600, 'Неверный приватный замок')
        срок_ожидания = time.monotonic() + 2
        while True:
            try:
                fcntl.flock(замок, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                требовать(time.monotonic() < срок_ожидания, 'Тайм-аут приватного замка обзора')
                time.sleep(.01)
        цель = корень / ключ
        if os.path.lexists(цель):
            каталог(цель)
            требовать({элемент_каталога.name for элемент_каталога in цель.iterdir()} == {'манифест.json', 'обзор.json', 'обзор.md'}, 'Неполный или чужой состав кэша')
            манифест = разобрать(прочитать_приватный(цель / 'манифест.json'))
            поля(манифест, ('схема', 'ключ', 'файлы'))
            требовать(манифест['схема'] == 'fum.кэш-доказательного-обзора.1' and манифест['ключ'] == ключ, 'Подменён ключ кэша')
            требовать(type(манифест['файлы']) is dict and set(манифест['файлы']) == {'обзор.json', 'обзор.md'}, 'Неверный манифест кэша')
            представления = {}
            for имя, ожидаемый_хэш in манифест['файлы'].items():
                представления[имя] = прочитать_приватный(цель / имя)
                требовать(хэш(представления[имя]) == ожидаемый_хэш, 'Повреждён кэш обзора')
            значение = разобрать(представления['обзор.json'])
            проверить(значение)
            требовать(представления['обзор.json'] == байты(значение) and представления['обзор.md'] == сформировать_разметку(значение), 'Кэш не совпадает с детерминированным представлением')
            return {'ключ': ключ, 'обзор': значение, 'повтор': True}
        значение = создать()
        проверить(значение)
        представления = {'обзор.json': байты(значение), 'обзор.md': сформировать_разметку(значение)}
        требовать(all(0 < len(данные) <= 2 * 1024 * 1024 for данные in представления.values()), 'Превышен предел представления обзора')
        представления['манифест.json'] = байты({'схема': 'fum.кэш-доказательного-обзора.1', 'ключ': ключ,
            'файлы': {имя: хэш(данные) for имя, данные in представления.items()}})
        временный = Path(tempfile.mkdtemp(prefix='.готовится-', dir=корень))
        for имя, данные in представления.items():
            with os.fdopen(os.open(временный / имя, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600), 'wb') as поток:
                поток.write(данные)
                поток.flush()
                os.fsync(поток.fileno())
        синхронизировать_каталог(временный)
        требовать(not os.path.lexists(цель), 'Цель кэша появилась при установке')
        os.rename(временный, цель)
        синхронизировать_каталог(корень)
        return {'ключ': ключ, 'обзор': значение, 'повтор': False}

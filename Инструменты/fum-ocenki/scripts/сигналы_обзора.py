"""Из точного механического отказа выводится кандидат автоматизации."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
from контракт_обзора import поля, разобрать, требовать, хэш

ОШИБКА_ИСТОРИИ = 'контрольная точка требует точный предпросмотр записей'


def прочитать(срез, строка):
    файл = срез.файл(строка['путь'])
    требовать(файл is not None, 'Отсутствует зарегистрированное наблюдение отказа')
    объект_файла, сырые = файл
    наблюдение = разобрать(сырые)
    поля(наблюдение, ('схема', 'ошибка', 'повтор_автоматически', 'профиль', 'длительность_наносекунды'))
    требовать(наблюдение['схема'] == 'fum.отказ-создания-коммита.1' and type(наблюдение['ошибка']) is str
        and наблюдение['повтор_автоматически'] is False and type(наблюдение['профиль']) is list
        and type(наблюдение['длительность_наносекунды']) is int and наблюдение['длительность_наносекунды'] >= 0, 'Неверный тип наблюдения отказа')
    if наблюдение['ошибка'] != ОШИБКА_ИСТОРИИ:
        return []
    кандидат = срез.файл(строка['доработка'])
    требовать(кандидат is not None, 'Нет долговечного кандидата доработки')
    return [{'имя': 'Автоматически актуализировать историю проверок', 'признак': 'механический отказ предкоммитного допуска',
        'состояние': 'кандидат доработки', 'путь': строка['путь'], 'blob': объект_файла, 'sha256': хэш(сырые),
        'доработка': строка['доработка'], 'доработка_sha256': хэш(кандидат[1]),
        'граница': 'Отказ подтверждён сохранённым сообщением создателя; первопричина и экономия требуют отдельной проверки.'}]

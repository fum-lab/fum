"""Короткое человекочитаемое представление того же доказательного JSON."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def код(значение):
    return str(значение).replace('`', '\\`').replace('\n', ' ').replace('\r', ' ')


def сформировать_разметку(обзор):
    строки = ['# Доказательный обзор FUM', '', 'Коммит `' + обзор['коммит'] + '`, дерево `' + обзор['дерево'] + '`.', '',
        обзор['граница'], '', '## Наблюдаемые компоненты', '']
    if not обзор['компоненты']:
        строки.append('Реестр компонентов отсутствует в этом C; состав компонентов неизвестен.')
    for строка_обзора in обзор['компоненты']:
        строки.append('- ' + код(строка_обзора['имя']) + ': ' + строка_обзора['состояние'] + '; исполнение — unknown.')
    строки += ['', '## Выбранные предкоммитные свидетельства', '']
    for строка_обзора in обзор['предкоммитные_проверки']:
        строки.append('- `' + строка_обзора['идентификатор'] + '`, класс ' + строка_обзора['класс'] + ', `' + код(строка_обзора['путь']) + '`; SHA-256 `' + строка_обзора['sha256'] + '`.')
    строки += ['', 'Эти записи выбраны допуском создателя и сохранены в C. Они не доказывают запуск тестов на созданном C.', '', '## Сохранённая промежуточная приёмка', '']
    if not обзор['приёмки']:
        строки.append('Типизированное решение в области реестра не найдено.')
    for строка_обзора in обзор['приёмки']:
        строки.append('- ' + код(строка_обзора['имя']) + ': `' + строка_обзора['коммит'] + '` включён в C; ' + код(строка_обзора['граница']))
    строки += ['', '## Кандидаты автоматизации', '']
    if not обзор['сигналы_автоматизации']:
        строки.append('В зарегистрированных наблюдениях нет известного механического отказа. Это не доказывает отсутствие других недоработок.')
    for строка_обзора in обзор['сигналы_автоматизации']:
        строки.append('- ' + код(строка_обзора['имя']) + ': `' + код(строка_обзора['доработка']) + '`; основание `' + строка_обзора['sha256'] + '`.')
    строки += ['', '## Неизвестные состояния', '']
    строки += ['- `' + имя_состояния + '`: unknown.' for имя_состояния in sorted(обзор['неизвестно'])]
    строки += ['', 'Наличие файлов, промежуточная приёмка, локальный профиль и общая готовность имеют разные границы.', '']
    return '\n'.join(строки).encode()

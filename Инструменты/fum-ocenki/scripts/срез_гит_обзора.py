import hashlib
import os
from pathlib import Path
import selectors
import signal
import subprocess
import time

from контракт_обзора import ОшибкаОбзора, физический, проверить_идентификатор_объекта, относительный, требовать, хэш


class СрезГит:
    def __init__(сам, корень, коммит, *, секунд=20):
        сам.корень = физический(корень)
        сам.коммит = проверить_идентификатор_объекта(коммит)
        сам.предел = time.monotonic() + секунд
        сам.объекты = {}
        сам.файлы = {}
        сам.число_вызовов = 0
        сам.сумма_байтов = 0

    def выполнить(сам, *аргументы, допустимые=(0,), предел=2 * 1024 * 1024):
        среда = {имя_поля: значение_поля for имя_поля, значение_поля in os.environ.items() if not имя_поля.startswith('GIT_')}
        среда.update(GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull, GIT_NO_LAZY_FETCH='1', GIT_TERMINAL_PROMPT='0')
        команда = ['git', '--literal-pathspecs', '--no-replace-objects', '--no-optional-locks', '-c', 'core.fsmonitor=false',
            '-C', str(сам.корень), *аргументы]
        требовать(time.monotonic() < сам.предел, 'Тайм-аут обзора')
        сам.число_вызовов += 1
        процесс = subprocess.Popen(команда, stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=среда, start_new_session=True)
        данные = {процесс.stdout: bytearray(), процесс.stderr: bytearray()}
        try:
            with selectors.DefaultSelector() as селектор:
                for поток in данные:
                    селектор.register(поток, selectors.EVENT_READ)
                while селектор.get_map():
                    остаток = min(10, сам.предел - time.monotonic())
                    требовать(остаток > 0, 'Тайм-аут обзора')
                    for событие, _ in селектор.select(остаток):
                        фрагмент = os.read(событие.fd, 65536)
                        if фрагмент:
                            данные[событие.fileobj].extend(фрагмент)
                            требовать(sum(map(len, данные.values())) <= предел, 'Превышен предел вывода Git')
                        else:
                            селектор.unregister(событие.fileobj)
                код = процесс.wait(timeout=max(.001, min(10, сам.предел - time.monotonic())))
            требовать(код in допустимые, 'Git не подтвердил ограниченное чтение: ' + str(код))
            return код, bytes(данные[процесс.stdout])
        except BaseException:
            if процесс.poll() is None:
                os.killpg(процесс.pid, signal.SIGKILL)
                процесс.wait()
            raise
        finally:
            процесс.stdout.close()
            процесс.stderr.close()

    def объект(сам, тип, идентификатор):
        идентификатор = проверить_идентификатор_объекта(идентификатор)
        ключ = (тип, идентификатор)
        if ключ not in сам.объекты:
            _, размер = сам.выполнить('cat-file', '-s', идентификатор, предел=256)
            требовать(0 <= int(размер) <= 2 * 1024 * 1024, 'Превышен предел объекта')
            _, сырые = сам.выполнить('cat-file', тип, идентификатор)
            алгоритм = 'sha1' if len(идентификатор) == 40 else 'sha256'
            ожидаемый = hashlib.new(алгоритм, тип.encode() + b' ' + str(len(сырые)).encode() + b'\0' + сырые).hexdigest()
            требовать(ожидаемый == идентификатор and len(сырые) == int(размер), 'OID не совпадает с байтами объекта')
            сам.сумма_байтов += len(сырые)
            требовать(сам.сумма_байтов <= 32 * 1024 * 1024, 'Превышен общий предел объектов обзора')
            сам.объекты[ключ] = сырые
        return сам.объекты[ключ]

    def метаданные(сам, коммит=None):
        сырые = сам.объект('commit', коммит or сам.коммит)
        заголовки, текст = сырые.split(b'\n\n', 1)
        поля = {}
        for строка in заголовки.splitlines():
            if строка.startswith(b' '):
                continue
            имя_поля, значение_поля = строка.split(b' ', 1)
            поля.setdefault(имя_поля.decode(), []).append(значение_поля.decode())
        for имя_поля in ('tree', 'author', 'committer'):
            требовать(len(поля.get(имя_поля, [])) == 1, 'Неоднозначные метаданные коммита')
        return {'коммит': коммит or сам.коммит, 'дерево': проверить_идентификатор_объекта(поля['tree'][0]),
            'родители': [проверить_идентификатор_объекта(родитель) for родитель in поля.get('parent', [])], 'автор': поля['author'][0],
            'коммиттер': поля['committer'][0], 'сообщение_sha256': хэш(текст)}

    def записи(сам, путь, *, рекурсивно=False):
        путь = относительный(путь)
        аргументы_гит = ['ls-tree', '-z', '--full-tree'] + (['-r'] if рекурсивно else [])
        _, сырые = сам.выполнить(*аргументы_гит, сам.коммит, '--', путь)
        результат = []
        for часть in сырые.split(b'\0'):
            if not часть:
                continue
            заголовок, имя = часть.split(b'\t', 1)
            режим, тип, объект = заголовок.decode().split(' ')
            результат.append((имя.decode(), режим, тип, проверить_идентификатор_объекта(объект)))
        требовать(len(результат) <= 256, 'Превышен предел путей обзора')
        return результат

    def файл(сам, путь):
        путь = относительный(путь)
        if путь not in сам.файлы:
            записи = сам.записи(путь)
            if not записи:
                сам.файлы[путь] = None
            else:
                требовать(len(записи) == 1 and записи[0][0] == путь and записи[0][1] in ('100644', '100755')
                    and записи[0][2] == 'blob', 'Ожидается обычный отслеживаемый файл')
                сам.файлы[путь] = (записи[0][3], сам.объект('blob', записи[0][3]))
        return сам.файлы[путь]

    def включает(сам, коммит):
        код, _ = сам.выполнить('merge-base', '--is-ancestor', проверить_идентификатор_объекта(коммит), сам.коммит, допустимые=(0, 1))
        return код == 0

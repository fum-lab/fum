"""Публичный результат создателя и выбранный им допуск без чтения native JSONL."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
import re

from контракт_обзора import байты, проверить_идентификатор_объекта, относительный, поля, прочитать_приватный, разобрать, требовать, хэш

ПОЛЯ_РЕЗУЛЬТАТА = {'коммит', 'дерево', 'родители', 'автор', 'коммиттер', 'сообщение_sha256'}


def прочитать(подготовка, квитанция):
    сырые = прочитать_приватный(подготовка)
    данные_подготовки = разобрать(сырые)
    данные_квитанции = разобрать(прочитать_приватный(квитанция))
    требовать(данные_подготовки.get('схема') in {'fum.подготовленный-коммит.4', 'fum.подготовленный-коммит.5', 'fum.подготовленный-коммит.6'}, 'Нужна поддерживаемая подготовка')
    требовать(данные_квитанции.get('схема') == 'fum.квитанция-создания-коммита.1' and данные_квитанции.get('состояние') == 'проверен'
        and данные_квитанции.get('подготовка_sha256') == хэш(сырые), 'Нужна проверенная квитанция этой подготовки')
    процесс = данные_квитанции.get('процесс', {})
    требовать(процесс.get('код') == 0 and процесс.get('исполнение_завершено') is True
        and процесс.get('тайм_аут') is False and процесс.get('прерывание') is None, 'Процесс создания не подтверждён')
    итог = данные_квитанции['результат']
    поля(итог, ПОЛЯ_РЕЗУЛЬТАТА)
    проверить_идентификатор_объекта(итог['коммит']); проверить_идентификатор_объекта(итог['дерево'])
    требовать(type(итог['родители']) is list and 1 <= len(итог['родители']) <= 16, 'Неверный состав родителей')
    for родитель in итог['родители']:
        проверить_идентификатор_объекта(родитель)
    ожидание = данные_квитанции['ожидание']
    требовать(итог['дерево'] == ожидание['дерево'] and итог['родители'] == ожидание['родители']
        and итог['сообщение_sha256'] == ожидание['сообщение_sha256'], 'Результат расходится с ожиданием')
    параметры = данные_подготовки['параметры']
    запрос = относительный(параметры['запрос'])
    требовать(re.fullmatch(r'Журнал/[^/]+/запрос\.md', запрос), 'Нужна исходная пара Журнала')
    выбранные_проверки = данные_квитанции['проверки']
    требовать(type(выбранные_проверки) is list and 0 < len(выбранные_проверки) <= 64 and len(set(выбранные_проверки)) == len(выбранные_проверки), 'Неверный выбранный набор')
    for идентификатор_проверки in выбранные_проверки:
        требовать(type(идентификатор_проверки) is str and re.fullmatch(r'[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}', идентификатор_проверки), 'Неверный UUID выбранной проверки')
    допуск = данные_квитанции['допуск']
    свидетельства = допуск['свидетельства']
    требовать(type(свидетельства) is list and 0 < len(свидетельства) <= 256, 'Неверный состав свидетельств')
    учтённые_идентификаторы = set()
    for пара in свидетельства:
        требовать(type(пара) is list and len(пара) == 2 and type(пара[0]) is str and пара[0] not in учтённые_идентификаторы
            and type(пара[1]) is str and re.fullmatch(r'[0-9a-f]{64}', пара[1]), 'Неверное или повторное свидетельство')
        учтённые_идентификаторы.add(пара[0])
    требовать(set(выбранные_проверки) <= учтённые_идентификаторы, 'Выбранная проверка не входит в допуск')
    for поле in ('гит', 'содержимое'):
        требовать(type(допуск[поле]) is str and re.fullmatch(r'sha256:[0-9a-f]{64}', допуск[поле]), 'Неверный отпечаток допуска')
    контекст = {'сессия': запрос, 'задача': параметры['задача'], 'проверки': выбранные_проверки,
        'свидетельства': свидетельства, 'гит': допуск['гит'], 'содержимое': допуск['содержимое'], 'результат': итог}
    return параметры['корень'], контекст, хэш(байты(контекст))

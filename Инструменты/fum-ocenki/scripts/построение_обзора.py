"""Доказательные факты и явные неизвестные вместо произвольной оценки зрелости."""
import hashlib
from pathlib import Path

КОД_ПРИ_ЗАГРУЗКЕ = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
from контракт_обзора import хэш
import приёмки_обзора
import сигналы_обзора


def построить(срез, метаданные, реестр, хэш_реестра, хэш_метода, хэш_контекста, проверки):
    компоненты = []
    for строка in реестр['компоненты']:
        файлы = []
        for путь in строка['файлы']:
            сведения_файла = срез.файл(путь)
            файлы.append({'путь': путь, 'состояние': 'присутствует' if сведения_файла is not None else 'не обнаружен',
                'blob': сведения_файла[0] if сведения_файла is not None else None, 'sha256': хэш(сведения_файла[1]) if сведения_файла is not None else None})
        компоненты.append({'имя': строка['имя'], 'состояние': 'присутствует' if all(сведения_файла['blob'] is not None for сведения_файла in файлы) else 'неполный состав',
            'файлы': файлы, 'исполнение': 'unknown'})
    return {'схема': 'fum.доказательный-обзор.1', **метаданные, 'граница': 'Неизменяемые объекты точного локального C; без повторного исполнения проверок.',
        'реестр_sha256': хэш_реестра, 'метод_sha256': хэш_метода, 'контекст_sha256': хэш_контекста,
        'компоненты': компоненты, 'предкоммитные_проверки': проверки,
        'приёмки': [приёмки_обзора.прочитать(срез, строка) for строка in реестр['приёмки']],
        'сигналы_автоматизации': [сигнал for строка in реестр['отказы'] for сигнал in сигналы_обзора.прочитать(срез, строка)],
        'неизвестно': {имя_состояния: 'unknown' for имя_состояния in ('проверки_на_коммите', 'полная_приёмка', 'текущая_доставка', 'интеграция_в_master',
            'обратный_приём', 'полная_готовность_конвейера', 'расход_токенов', 'стоимость_принятого_результата',
            'время_полного_цикла', 'независимое_восстановление_отпечатков')}}

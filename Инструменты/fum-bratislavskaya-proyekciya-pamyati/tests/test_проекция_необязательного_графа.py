"""Проекция сохраняет адрес локального графа, не требуя пользовательского файла."""

import json
from pathlib import Path
import unittest
from unittest import mock

import test_братиславская_проекция_памяти as основа


модуль = основа.модуль
исходный_путь = "Журнал/2026-06-23_13-55-41_MSK/отчёт.md"


def политика():
    return json.loads((основа.СЦЕНАРИЙ.parents[1] / "контракт-v2.json").read_text())


class ПроверкаПроекцииНеобязательногоГрафа(unittest.TestCase):
    _выполнить_команду_контроля_версий = основа.ПроверкаКонтрактаБратиславскойПроекции._выполнить_команду_контроля_версий
    _записать = основа.ПроверкаКонтрактаБратиславскойПроекции._записать
    _зафиксировать = основа.ПроверкаКонтрактаБратиславскойПроекции._зафиксировать

    def _преобразовать(сам, строки):
        соответствия = {"Журнал": "Zhurnal", "отчёт": "otchyot", "Граф": "Graf"}
        for исходное, целевое in соответствия.items():
            строки = [строка.replace(исходное, целевое) for строка in строки]
        return строки

    def _подготовить(сам, адрес="../../.obsidian/graph.json"):
        сам._записать(".gitignore", ".obsidian/graph.json\nProyekcii/\nalias\n")
        сам._записать(исходный_путь, f"# History\n\n[Граф]({адрес})\n")
        сам._зафиксировать()

    def _выходы(сам):
        план = модуль.построить_план(сам.корень, политика(), сам._преобразовать)
        return план, модуль.сформировать_выходы(сам.корень, план, сам._преобразовать)

    def _применить_и_проверить(сам):
        модуль.применить_поколение(сам.корень, политика(), сам._преобразовать)
        манифест = json.loads((сам.корень / политика()["путь_манифеста"]).read_text())
        проверка = модуль.проверить_манифест(
            сам.корень, политика(), манифест,
            сам.корень / политика()["целевая_область"], сам._преобразовать)
        сам.assertEqual(проверка["состояние"], "действителен")
        сам.assertNotIn(".obsidian/graph.json", {запись["исходный_путь"] for запись in манифест["записи"]})
        return манифест

    def test_отсутствующий_граф_не_создаётся_при_применении_и_проверке(сам):
        сам._подготовить()
        for каталог_существует in (False, True):
            with сам.subTest(каталог_существует=каталог_существует):
                if каталог_существует:
                    (сам.корень / ".obsidian").mkdir()
                сам._применить_и_проверить()
                сам.assertFalse((сам.корень / ".obsidian/graph.json").exists())
                сам.assertEqual((сам.корень / ".obsidian").exists(), каталог_существует)

    def test_существующий_граф_сохраняет_байты_идентичность_и_время(сам):
        сам._подготовить()
        граф = сам._записать(".obsidian/graph.json", b'{"scale": 1.234, "search": "user selection"}\n')
        исходные = граф.read_bytes()
        состояние = граф.stat()
        сам._применить_и_проверить()
        сам.assertEqual(граф.read_bytes(), исходные)
        сам.assertEqual((граф.stat().st_ino, граф.stat().st_mtime_ns),
                       (состояние.st_ino, состояние.st_mtime_ns))

    def test_ссылка_из_производного_файла_ведёт_в_канонический_граф(сам):
        сам._подготовить()
        план, выходы = сам._выходы()
        запись = next(запись for запись in план["записи"] if запись["исходный_путь"] == исходный_путь)
        текст = выходы[запись["целевой_путь"]].decode()
        сам.assertIn("[Graf](../../../../../.obsidian/graph.json)", текст)
        анализатор = модуль.модуль_структурной_разметки()
        токен = list(анализатор.markdown_link_tokens(текст, анализатор.markdown_hidden_mask(текст)))[0]
        назначение = анализатор.resolve_destination(
            токен, сам.корень / запись["целевой_путь"], сам.корень, Path(запись["целевой_путь"]))
        сам.assertEqual(назначение.target, сам.корень / ".obsidian/graph.json")
        сам.assertFalse(назначение.target.exists())

    def test_прочие_отсутствующие_цели_и_обходы_сохраняют_отказ(сам):
        сам._подготовить()
        (сам.корень / ".obsidian").mkdir()
        (сам.корень / "alias").symlink_to(".obsidian", target_is_directory=True)
        for адрес in (
            "../../.obsidian/Graph.json", "../../.Obsidian/graph.json",
            "../../.obsidian/graph.json.bak", "../../.obsidian/other.json",
            "../../other/.obsidian/graph.json", "../../../.obsidian/graph.json",
            "../../alias/graph.json", "../../missing/../.obsidian/graph.json",
            str(сам.корень / ".obsidian/graph.json"), "../../missing.md",
        ):
            with сам.subTest(адрес=адрес):
                сам._записать(исходный_путь, f"# History\n\n[Граф]({адрес})\n")
                with сам.assertRaises(модуль.ОшибкаКонтракта):
                    сам._выходы()
        сам._записать(исходный_путь, "# History\n\n[Граф](../../.obsidian/graph.json)\n")
        (сам.корень / ".obsidian/graph.json").symlink_to("missing.json")
        with сам.assertRaises(модуль.ОшибкаКонтракта):
            сам._выходы()

    def test_регистр_физического_предка_не_скрывается_отсутствием_графа(сам):
        сам._подготовить()
        (сам.корень / ".Obsidian").mkdir()
        with сам.assertRaises(модуль.ОшибкаКонтракта):
            сам._выходы()

    def test_неигнорируемый_отсутствующий_граф_не_получает_исключения(сам):
        сам._подготовить()
        сам._выходы()
        сам._записать(".gitignore", "Proyekcii/\n")
        with сам.assertRaises(модуль.ОшибкаКонтракта):
            сам._выходы()

    def test_изменение_игнорирования_во_время_формирования_закрывает_выход(сам):
        сам._подготовить()
        план = модуль.построить_план(сам.корень, политика(), сам._преобразовать)
        исходная_проверка = модуль.путь_игнорируется_репозиторием
        изменено = False

        def проверить_и_изменить(корень, путь):
            nonlocal изменено
            результат = исходная_проверка(корень, путь)
            if путь == ".obsidian/graph.json" and результат and not изменено:
                изменено = True
                сам._записать(".gitignore", "Proyekcii/\n")
            return результат

        with mock.patch.object(модуль, "путь_игнорируется_репозиторием", side_effect=проверить_и_изменить):
            with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "[Ии]гнор"):
                модуль.сформировать_выходы(сам.корень, план, сам._преобразовать)


setattr(ПроверкаПроекцииНеобязательногоГрафа, "setUp",
        основа.ПроверкаКонтрактаБратиславскойПроекции.подготовить_испытание)
setattr(ПроверкаПроекцииНеобязательногоГрафа, "tearDown",
        основа.ПроверкаКонтрактаБратиславскойПроекции.завершить_испытание)


if __name__ == "__main__":
    unittest.main()

"""Точный файл Git mailmap и переход с закреплённого прежнего поколения."""

import json
from unittest import TestCase, mock

import test_братиславская_проекция_памяти as проверки_проекции


class ПроверкаКартыАвторов(TestCase):
    def подготовить(сам):
        фикстура = проверки_проекции.ПроверкаКонтрактаБратиславскойПроекции()
        фикстура.подготовить_испытание()
        сам.addCleanup(фикстура.завершить_испытание)
        модуль = проверки_проекции.модуль
        каталог = проверки_проекции.СЦЕНАРИЙ.parent.parent
        политика = модуль.загрузить_политику(каталог / "контракт-v2.json")
        return фикстура, модуль, каталог, политика

    def test_точная_карта_сохраняет_байты_и_проверяется_независимо(сам):
        фикстура, модуль, _, политика = сам.подготовить()
        байты = "# Ёж\r\nFUM Интегратор <fum@local> FUMИнтегратор <fum@local>\r\n".encode("utf-8")
        фикстура._записать(".mailmap", байты)
        фикстура._зафиксировать()
        преобразователь = фикстура._преобразователь()
        модуль.применить_поколение(фикстура.корень, политика, преобразователь)
        манифест = модуль.загрузить_машинные_данные(
            фикстура.корень / политика["путь_манифеста"], "манифест"
        )
        запись = next(запись for запись in манифест["записи"]
                      if запись["исходный_путь"] == ".mailmap")
        сам.assertEqual(запись["класс_содержимого"], "прочий_точный_формат")
        сам.assertEqual(запись["действие_содержимого"], "сохранить_байты")
        сам.assertEqual((фикстура.корень / запись["целевой_путь"]).read_bytes(), байты)
        модуль.проверить_манифест(
            фикстура.корень, политика, манифест,
            фикстура.корень / политика["целевая_область"], преобразователь,
        )

    def test_похожие_текстовые_пути_не_получают_допуск(сам):
        for путь in (".MAILMAP", "вложено/.mailmap", ".mailmap.bak",
                     ".mailmaps", "имя.mailmap"):
            with сам.subTest(путь=путь):
                фикстура, модуль, _, политика = сам.подготовить()
                фикстура._записать(путь, "Имя <mail@example.invalid>\n")
                фикстура._зафиксировать()
                with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "Неизвестный формат"):
                    модуль.построить_план(
                        фикстура.корень, политика,
                        фикстура._преобразователь({"вложено": "vlozheno", "имя.mailmap": "imya.mailmap"}),
                    )

    def test_ссылка_с_именем_карты_не_разрешена(сам):
        фикстура, модуль, _, политика = сам.подготовить()
        фикстура._записать("карта.txt", "Имя <mail@example.invalid>\n")
        (фикстура.корень / ".mailmap").symlink_to("карта.txt")
        фикстура._зафиксировать()
        with сам.assertRaises(модуль.ОшибкаКонтракта):
            модуль.построить_план(
                фикстура.корень, политика, фикстура._преобразователь()
            )

    def прежнее_поколение(сам):
        фикстура, модуль, каталог, политика = сам.подготовить()
        исходник = каталог / "tests/фикстуры/поколение-до-карты-авторов-v2.json"
        данные = json.loads(исходник.read_text())
        сам.assertEqual(данные["происхождение"]["коммит"],
                        "9a410dea90c09e24954fab7e4c28f613b8bda06f")
        for путь, байты in данные["исходники_hex"].items():
            фикстура._записать(путь, bytes.fromhex(байты))
        фикстура._зафиксировать()
        for путь, байты in данные["выходы_hex"].items():
            фикстура._записать(путь, bytes.fromhex(байты))
        фикстура._записать_манифест(политика, данные["манифест"])
        return фикстура, модуль, политика, данные

    def test_старое_поколение_переходит_с_новой_картой_и_точным_повтором(сам):
        фикстура, модуль, политика, данные = сам.прежнее_поколение()
        преобразователь = фикстура._преобразователь(данные["соответствия"])
        with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "хэш политики изменился"):
            модуль.проверить_манифест(
                фикстура.корень, политика, данные["манифест"],
                фикстура.корень / политика["целевая_область"], преобразователь,
            )
        фикстура._записать(".mailmap", "# Ёж\r\n".encode("utf-8"))
        модуль.применить_поколение(фикстура.корень, политика, преобразователь)
        манифест = модуль.загрузить_машинные_данные(
            фикстура.корень / политика["путь_манифеста"], "манифест"
        )
        модуль.проверить_манифест(
            фикстура.корень, политика, манифест,
            фикстура.корень / политика["целевая_область"], преобразователь,
        )
        снимок = фикстура._снимок_поколения(политика)
        модуль.применить_поколение(фикстура.корень, политика, преобразователь)
        сам.assertEqual(снимок, фикстура._снимок_поколения(политика))

    def test_подмена_закреплённого_контракта_сохраняет_старое_дерево(сам):
        фикстура, модуль, политика, данные = сам.прежнее_поколение()
        снимок = фикстура._снимок_поколения(политика)
        чтение = модуль.безопасно_прочитать_обычный_файл

        def прочитать(корень, путь, *аргументы, **именованные):
            if путь == "совместимость/контракт-v2-до-карты-авторов.json":
                return b"{}\n"
            return чтение(корень, путь, *аргументы, **именованные)

        with mock.patch.object(модуль, "безопасно_прочитать_обычный_файл",
                               side_effect=прочитать):
            with сам.assertRaisesRegex(модуль.ОшибкаКонтракта, "политик"):
                модуль.применить_поколение(
                    фикстура.корень, политика,
                    фикстура._преобразователь(данные["соответствия"]),
                )
        сам.assertEqual(снимок, фикстура._снимок_поколения(политика))

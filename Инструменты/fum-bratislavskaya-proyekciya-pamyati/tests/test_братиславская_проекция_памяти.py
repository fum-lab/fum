    def _записать(сам, путь, данные, исполняемый=False):
        цель = сам.корень / путь
        цель.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(данные, str):
            цель.write_text(данные, encoding="utf-8")
        else:
            цель.write_bytes(данные)
        if исполняемый:
            цель.chmod(0o755)
        return цель


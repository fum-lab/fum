import Foundation

public enum ИнтерфейсПерехода {
    public static func выполнить(_ аргументы: [String]) async throws -> Data {
        guard let команда = аргументы.first else { throw ОшибкаПерехода.отказ("нужна команда: план, переименовать, сверить") }
        var поля: [String: String] = [:]
        let хвост = Array(аргументы.dropFirst())
        try требовать(хвост.count % 2 == 0, "ожидались пары --параметр значение")
        for номер in stride(from: 0, to: хвост.count, by: 2) {
            let ключ = хвост[номер]
            try требовать(ключ.hasPrefix("--") && поля[ключ] == nil, "неизвестный/повторный параметр")
            поля[ключ] = хвост[номер + 1]
        }
        func обязательное(_ ключ: String) throws -> String {
            guard let значение = поля[ключ], !значение.isEmpty else {
                throw ОшибкаПерехода.отказ("нет " + ключ)
            }
            return значение
        }
        func выбранный(_ путь: String, _ отпечаток: String) throws -> Ресурс {
            Ресурс(путь: try обязательное(путь), хэш: try обязательное(отпечаток))
        }
        let выбор = try выбранный("--выбор-корня", "--хэш-выбора")
        if команда == "план" {
            try требовать(Set(поля.keys) == ["--выбор-корня", "--хэш-выбора", "--задание", "--выход"],
                           "лишний параметр плана")
            let задание = try декодировать(ЗаданиеПерехода.self,
                Файлы.прочитать(обязательное("--задание"), приватный: true))
            let план = try Планировщик.построить(задание, выбор: выбор)
            let данные = try план.байты()
            try Файлы.записатьНовый(Файлы.физический(обязательное("--выход")), данные)
            return try кодировать(["план_sha256": хэш(данные), "новая_ветка": план.новаяВетка,
                                   "установка": "план не разрешает эффект"])
        }
        try требовать(["переименовать", "сверить"].contains(команда), "неподдержанная команда checkpoint")
        let разрешённые: Set<String> = ["--выбор-корня", "--хэш-выбора", "--план", "--хэш-плана"]
        try требовать(Set(поля.keys).isSubset(of: разрешённые), "лишний параметр продолжения")
        let источник = try выбранный("--план", "--хэш-плана")
        let данные = try Файлы.ресурс(источник)
        let план = try декодировать(План.self, данные)
        try требовать(try план.байты() == данные, "неканонический/неизвестный план")
        let переход = try ПереходВетки(план: план, выборКорня: выбор, создатьПротокол: команда != "сверить")
        if команда == "сверить" { return try await кодировать(переход.сверить()) }
        return try await кодировать(переход.переименовать())
    }
}

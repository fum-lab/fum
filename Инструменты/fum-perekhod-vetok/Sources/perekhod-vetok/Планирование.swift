import Foundation
import Darwin

public enum Планировщик {
    public static func построить(_ задание: ЗаданиеПерехода, выбор: Ресурс) throws -> План {
        try требовать(задание.схема == "fum.задание-перехода-ветки.1", "неизвестное задание")
        try требовать(задание.репозиторий.номерХостинга > 0, "нужен реальный идентификатор хостинга")
        for строка in [задание.операция, задание.владелец, задание.чат] {
            try требовать(UUID(uuidString: строка)?.uuidString.lowercased() == строка, "неверный UUID")
        }
        try требовать(задание.владелец == задание.чат, "чат не принадлежит владельцу")
        let сырые = try Файлы.ресурс(выбор)
        let корень = try декодировать(ВыбранныйКорень.self, сырые)
        try требовать(корень.схема == "fum.выбор-корня-перехода.1", "неизвестный выбор корня")
        _ = try Файлы.ресурс(корень.основание)
        try проверитьВладельца(задание, средаОбязательна: false)
        let гит = try Гит(задание)
        try проверитьГраницу(задание, корень: корень, гит: гит, средаОбязательна: false)
        let преобразование = try гит.команды.выполнить(
            задание.преобразователь.путь, [],
            вход: JSONEncoder().encode(задание.названияНаправления))
        try требовать(преобразование.код == 0, "братиславский преобразователь отказал")
        let слова = try декодировать([String].self, преобразование.вывод)
        try требовать(!слова.isEmpty && слова.count == задание.названияНаправления.count,
                       "неполный результат преобразования")
        let компоненты = try слова.map { try ИменаПерехода.компонент($0) }
        let префикс = "refs/heads/" + задание.репозиторий.полноеИмя + "/"
        try требовать(корень.ветка.hasPrefix(префикс), "выбранный root ref вне пространства репозитория")
        let окончание = String(корень.ветка.dropFirst(префикс.count))
        try требовать(!окончание.contains("/"), "неоднозначный root ref")
        let конечныйКомпонент = try ИменаПерехода.компонент(окончание)
        let новая = префикс + компоненты.joined(separator: "/") + "/" + конечныйКомпонент
        try ИменаПерехода.проверитьВетку(новая)
        try требовать(новая != задание.прежняяВетка && новая != корень.ветка, "не новая адресная ветка")
        try проверитьЦель(новая, задание: задание, гит: гит)
        let локальные = try гит.ссылки()
        try ИменаПерехода.проверитьКоллизии(новая,
            существующие: локальные.keys.filter { $0.hasPrefix("refs/heads/") })
        let удалённые = try гит.сервер()
        try ИменаПерехода.проверитьКоллизии(новая,
            существующие: удалённые.keys.filter { $0.hasPrefix("refs/heads/") })
        try требовать(удалённые[корень.ветка] == корень.коммит, "ROOT L ещё не подтверждён на origin")
        _ = try Файлы.приватныйКаталог(URL(fileURLWithPath: задание.каталогПротокола)
            .deletingLastPathComponent().path)
        try требовать(!FileManager.default.fileExists(atPath: задание.каталогПротокола),
                       "каталог операции уже существует")
        let имяКаталога = URL(fileURLWithPath: задание.каталогПротокола).lastPathComponent
        try требовать(try ИменаПерехода.компонент(имяКаталога) == имяКаталога,
                       "новый каталог протокола должен быть ASCII lowercase")
        let начало = try нативноеНачало(задание)
        return План(схема: "fum.план-перехода-ветки.1", задание: задание,
                    выборКорня: корень, хэшВыбораКорня: хэш(сырые),
                    новаяВетка: новая, названиеЧата: String(новая.dropFirst("refs/heads/".count)),
                    прежнийУдалённыйОбъект: удалённые[задание.прежняяВетка],
                    идентичностьОбщегоКаталога: try идентичностьКаталога(задание.репозиторий.общийКаталогГит),
                    хэшНативногоНачала: хэш(начало))
    }
    static func нативноеНачало(_ задание: ЗаданиеПерехода) throws -> Data {
        let адрес = try Файлы.физический(задание.исходникДиалога)
        let поток = try FileHandle(forReadingFrom: адрес)
        defer { try? поток.close() }
        var префикс = Data()
        while префикс.firstIndex(of: 10) == nil && префикс.count < 2_097_152 {
            let часть = try поток.read(upToCount: 65_536) ?? Data()
            if часть.isEmpty { break }
            префикс.append(часть)
        }
        guard let конец = префикс.firstIndex(of: 10) else {
            throw ОшибкаПерехода.отказ("нет полной нативной session_meta")
        }
        let строка = префикс.prefix(through: конец)
        let объект = try JSONSerialization.jsonObject(with: строка) as? [String: Any]
        let мета = объект?["payload"] as? [String: Any]
        try требовать(объект?["type"] as? String == "session_meta" &&
                       мета?["id"] as? String == задание.владелец &&
                       мета?["cwd"] as? String == задание.рабочееДерево, "чужая нативная задача")
        return Data(строка)
    }
    static func проверитьВладельца(_ задание: ЗаданиеПерехода, средаОбязательна: Bool = true) throws {
        try требовать(!средаОбязательна || ProcessInfo.processInfo.environment["CODEX_THREAD_ID"] == задание.владелец,
                       "чужой UUID среды; effect выполняет владелец")
        _ = try нативноеНачало(задание)
        _ = try Файлы.физический(задание.рабочееДерево)
    }
    static func идентичностьКаталога(_ путь: String) throws -> String {
        _ = try Файлы.физический(путь)
        var сведения = stat()
        try требовать(lstat(путь, &сведения) == 0 && (сведения.st_mode & S_IFMT) == S_IFDIR,
                       "нет физического common Git")
        return "\(сведения.st_dev):\(сведения.st_ino)"
    }
    static func проверитьГраницу(_ задание: ЗаданиеПерехода, корень: ВыбранныйКорень,
                                  гит: Гит, начальная: Bool = true, средаОбязательна: Bool = true) throws {
        try проверитьВладельца(задание, средаОбязательна: средаОбязательна)
        _ = try Файлы.ресурс(задание.исполняемыйГит)
        _ = try Файлы.ресурс(задание.преобразователь)
        _ = try Файлы.ресурс(корень.основание)
        for ресурс in задание.ресурсы { _ = try Файлы.ресурс(ресурс) }
        for объект in [задание.ожидаемыйКоммит, корень.коммит] {
            try требовать(объект.utf8.count == 40 && объект.utf8.allSatisfy {
                ($0 >= 48 && $0 <= 57) || ($0 >= 97 && $0 <= 102)
            }, "нужен полный OID SHA-1")
            try требовать(try гит.прочитать(["cat-file", "-t", объект]) == "commit", "S/L не commit-объект")
        }
        try требовать(try гит.прочитать(["remote", "get-url", "--all", "origin"])
                       == задание.репозиторий.адресСервера, "чужой/неединственный origin")
        try требовать(try гит.прочитать(["remote", "get-url", "--push", "--all", "origin"])
                       == задание.репозиторий.адресСервера, "чужой push URL")
        try требовать(try гит.прочитать(["rev-parse", "--path-format=absolute", "--git-common-dir"])
                       == задание.репозиторий.общийКаталогГит, "чужой common Git")
        try требовать(try гит.прочитать(["rev-parse", "--verify", корень.ветка]) == корень.коммит,
                       "изменился выбранный ROOT L")
        let рабочие = try гит.прочитать(["worktree", "list", "--porcelain", "-z"])
        let текущаяВетка = try гит.прочитать(["symbolic-ref", "HEAD"])
        var владельцы: [String] = []
        var текущиеВладельцы: [String] = []
        for блок in рабочие.components(separatedBy: "\0\0") {
            let строки = блок.components(separatedBy: "\0")
            if строки.contains("branch " + задание.прежняяВетка) {
                владельцы += строки.filter { $0.hasPrefix("worktree ") }.map { String($0.dropFirst(9)) }
            }
            if строки.contains("branch " + текущаяВетка) {
                текущиеВладельцы += строки.filter { $0.hasPrefix("worktree ") }.map { String($0.dropFirst(9)) }
            }
        }
        try требовать(текущиеВладельцы == [задание.рабочееДерево], "ref занят другим checkout; режим проекции не поддержан")
        if начальная {
            try требовать(владельцы == [задание.рабочееДерево], "неединственный владелец старого ref")
            try требовать(try гит.прочитать(["symbolic-ref", "HEAD"]) == задание.прежняяВетка,
                           "другая текущая ветка")
            try требовать(try гит.прочитать(["rev-parse", "HEAD"]) == задание.ожидаемыйКоммит,
                           "изменился исходный HEAD")
            try требовать(try гит.прочитать(["status", "--porcelain=v1", "--untracked-files=all"]).isEmpty,
                           "рабочее дерево не чистое")
        }
    }
    static func проверитьЦель(_ новая: String, задание: ЗаданиеПерехода, гит: Гит,
                              допускСвоего: Bool = false) throws {
        let рабочие = try гит.прочитать(["worktree", "list", "--porcelain", "-z"])
        var свои = 0
        for блок in рабочие.components(separatedBy: "\0\0") {
            let строки = блок.components(separatedBy: "\0")
            guard let строка = строки.first(where: { $0.hasPrefix("branch ") }) else { continue }
            let ветка = String(строка.dropFirst(7))
            let свой = допускСвоего && ветка == новая && строки.contains("worktree " + задание.рабочееДерево)
            if свой { свои += 1; continue }
            try ИменаПерехода.проверитьКоллизии(новая, существующие: [ветка])
        }
        try требовать(!допускСвоего || свои == 1, "неединственный владелец нового ref")
    }
}

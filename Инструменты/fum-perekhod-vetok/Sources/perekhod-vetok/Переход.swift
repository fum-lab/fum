import Foundation
import Darwin

public actor ПереходВетки {
    let план: План
    let гит: Гит
    let каталог: URL
    let блокировка: Int32
    let наблюдатель: (@Sendable (String) throws -> Void)?
    let выборКорня: Ресурс
    let разрешеныЭффекты: Bool

    public init(план: План, выборКорня: Ресурс,
                наблюдатель: (@Sendable (String) throws -> Void)? = nil,
                создатьПротокол: Bool = true) throws {
        try требовать(план.схема == "fum.план-перехода-ветки.1", "неизвестный план")
        let выбор = try Файлы.ресурс(выборКорня)
        try требовать(хэш(выбор) == план.хэшВыбораКорня &&
                       декодировать(ВыбранныйКорень.self, выбор) == план.выборКорня, "другой ROOT-выбор")
        try Планировщик.проверитьВладельца(план.задание)
        let исполнитель = try Гит(план.задание)
        try Планировщик.проверитьГраницу(план.задание, корень: план.выборКорня,
                                         гит: исполнитель, начальная: false)
        try Планировщик.проверитьЦель(план.новаяВетка, задание: план.задание, гит: исполнитель,
            допускСвоего: исполнитель.прочитать(["symbolic-ref", "HEAD"]) == план.новаяВетка)
        let административный = try исполнитель.прочитать(["rev-parse", "--absolute-git-dir"])
        let путьЗамка = URL(fileURLWithPath: административный).appendingPathComponent("fum-perekhod-vetok.lock")
        let дескриптор = создатьПротокол
            ? open(путьЗамка.path, O_RDWR | O_CREAT | O_NOFOLLOW, 0o600)
            : open(путьЗамка.path, O_RDONLY | O_NOFOLLOW)
        try требовать(дескриптор >= 0 || !создатьПротокол && errno == ENOENT, "не удалось открыть межпроцессный замок")
        var сведения = stat()
        guard дескриптор < 0 || fstat(дескриптор, &сведения) == 0 && (сведения.st_mode & S_IFMT) == S_IFREG && сведения.st_nlink == 1 &&
              сведения.st_uid == getuid() && (сведения.st_mode & 0o777) == 0o600 &&
              flock(дескриптор, LOCK_EX | LOCK_NB) == 0 else {
            close(дескриптор)
            throw ОшибкаПерехода.отказ("другой писатель/небезопасный замок")
        }
        do {
            let адрес = URL(fileURLWithPath: план.задание.каталогПротокола)
            let существует = Файлы.существует(адрес)
            let папка = существует || создатьПротокол
                ? try Файлы.приватныйКаталог(адрес.path, создать: создатьПротокол)
                : try Файлы.физический(адрес.path)
            let путьПлана = папка.appendingPathComponent("план.json")
            if Файлы.существует(путьПлана) {
                try требовать(try Файлы.прочитать(путьПлана.path, приватный: true) == план.байты(),
                               "другой или неполный протокол")
            } else if создатьПротокол {
                try требовать(try FileManager.default.contentsOfDirectory(atPath: папка.path).isEmpty,
                               "неизвестный остаток операции")
                try Файлы.записатьНовый(путьПлана, план.байты())
            } else {
                try требовать(!существует, "существующий протокол не содержит выбранного плана")
            }
            self.каталог = папка
        } catch {
            close(дескриптор); throw error
        }
        self.план = план; self.гит = исполнитель
        self.блокировка = дескриптор; self.наблюдатель = наблюдатель
        self.выборКорня = выборКорня
        self.разрешеныЭффекты = создатьПротокол
    }
    deinit { if блокировка >= 0 { close(блокировка) } }

    func путь(_ фаза: String, _ вид: String) -> URL {
        каталог.appendingPathComponent(фаза + "-" + вид + ".json")
    }
    func ресурсКорняНеИзменился() throws {
        try требовать(хэш(Файлы.ресурс(выборКорня)) == план.хэшВыбораКорня, "изменился независимый selector")
        try Планировщик.проверитьГраницу(план.задание, корень: план.выборКорня,
                                         гит: гит, начальная: false)
        try Планировщик.проверитьЦель(план.новаяВетка, задание: план.задание, гит: гит,
            допускСвоего: гит.прочитать(["symbolic-ref", "HEAD"]) == план.новаяВетка)
        try требовать(try Планировщик.идентичностьКаталога(план.задание.репозиторий.общийКаталогГит)
                       == план.идентичностьОбщегоКаталога, "изменился common Git")
        try требовать(хэш(Планировщик.нативноеНачало(план.задание)) == план.хэшНативногоНачала,
                       "изменилось нативное начало")
    }
    func запись(_ вид: String) throws -> СохранённыйИсход? {
        let адрес = путь("01-переименование", вид)
        if !Файлы.существует(адрес) { return nil }
        let данные = try Файлы.прочитать(адрес.path, приватный: true)
        let запись = try декодировать(СохранённыйИсход.self, данные)
        let схемы = ["намерение": "fum.намерение-перехода.1", "передача": "fum.передача-эффекта.1", "исход": "fum.исход-перехода.1"]
        try требовать(запись.схема == схемы[вид] && запись.фаза == "01-переименование" &&
                       запись.хэшПлана == план.отпечаток() && запись.объект == план.задание.ожидаемыйКоммит &&
                       кодировать(запись) == данные, "чужая/повреждённая запись протокола")
        return запись
    }
    func состояние() throws -> String {
        try ресурсКорняНеИзменился()
        let разрешённые: Set<String> = ["план.json", "01-переименование-намерение.json", "01-переименование-передача.json", "01-переименование-исход.json"]
        if Файлы.существует(каталог) {
            try требовать(Set(try FileManager.default.contentsOfDirectory(atPath: каталог.path)).isSubset(of: разрешённые),
                           "неизвестные файлы протокола")
        }
        let намерение = try запись("намерение")
        let передача = try запись("передача")
        let исход = try запись("исход")
        try требовать((передача == nil && исход == nil) || намерение != nil, "нет исходного намерения")
        for запись in [намерение, передача, исход].compactMap({ $0 }) {
            try требовать(запись.код == 0, "предыдущий отказ сохраняется; команда не повторена")
        }
        let ссылки = try гит.ссылки()
        let текущая = try гит.прочитать(["symbolic-ref", "HEAD"])
        let коммит = try гит.прочитать(["rev-parse", "HEAD"])
        try требовать(коммит == план.задание.ожидаемыйКоммит, "дрейф HEAD")
        let до = текущая == план.задание.прежняяВетка && ссылки[план.задание.прежняяВетка] == коммит && ссылки[план.новаяВетка] == nil
        let после = текущая == план.новаяВетка && ссылки[план.новаяВетка] == коммит && ссылки[план.задание.прежняяВетка] == nil
        try требовать(до || после && намерение != nil, "дрейф refs или новая ветка без своего намерения")
        if исход != nil {
            try требовать(после, "дрейф подтверждённого постусловия")
            return "локальная-ветка-переименована"
        }
        if после { return "переименование-наблюдено" }
        if передача != nil { return "неизвестный-исход" }
        return намерение == nil ? "до-переименования" : "намерение-не-передано"
    }
    func проверитьСервер(_ после: Bool) throws {
        let ссылки = try гит.сервер()
        try требовать(ссылки[план.выборКорня.ветка] == план.выборКорня.коммит, "дрейф ROOT L на origin")
        try требовать(ссылки[план.задание.прежняяВетка] == план.прежнийУдалённыйОбъект, "прежний remote должен сохраниться")
        try ИменаПерехода.проверитьКоллизии(план.новаяВетка,
            существующие: ссылки.keys.filter { $0.hasPrefix("refs/heads/") })
    }
    func эффект(_ фаза: String, аргументы: [String], объект: String,
                проверитьРезультат: () throws -> Bool, разрешёнКонфликт: Bool = false) throws {
        try ресурсКорняНеИзменился()
        let итог = путь(фаза, "исход")
        if Файлы.существует(итог) {
            let запись = try декодировать(СохранённыйИсход.self,
                Файлы.прочитать(итог.path, приватный: true))
            try требовать(запись.хэшПлана == план.отпечаток() && запись.фаза == фаза &&
                           (запись.код == 0 || разрешёнКонфликт && запись.код == 1),
                           "предыдущий отказ или чужой исход; эффект не повторён")
            try требовать(try проверитьРезультат(), "дрейф подтверждённого постусловия; команда не повторена")
            return
        }
        let намерение = путь(фаза, "намерение")
        let передача = путь(фаза, "передача")
        if Файлы.существует(намерение) {
            let запись = try декодировать(СохранённыйИсход.self,
                Файлы.прочитать(намерение.path, приватный: true))
            try требовать(запись.хэшПлана == план.отпечаток() && запись.объект == объект, "чужое намерение")
            if try проверитьРезультат() {
                try Файлы.записатьНовый(итог, кодировать(СохранённыйИсход(
                    схема: "fum.исход-перехода.1", фаза: фаза, хэшПлана: план.отпечаток(),
                    код: 0, объект: объект, пояснение: "reconcile: точное постусловие, без повтора команды")))
                return
            }
            try требовать(!Файлы.существует(передача), "неизвестный исход переданного эффекта; только сверка")
        } else {
            try Файлы.записатьНовый(намерение, кодировать(СохранённыйИсход(
                схема: "fum.намерение-перехода.1", фаза: фаза, хэшПлана: план.отпечаток(),
                код: 0, объект: объект, пояснение: "до передачи команды")))
        }
        try наблюдатель?(фаза + ":после-намерения")
        try Файлы.записатьНовый(передача, кодировать(СохранённыйИсход(
            схема: "fum.передача-эффекта.1", фаза: фаза, хэшПлана: план.отпечаток(),
            код: 0, объект: объект, пояснение: "команда может быть начата; отсутствие ответа не разрешает повтор")))
        let ответ = try гит.вызвать(аргументы)
        try наблюдатель?(фаза + ":после-команды")
        let постусловие = try проверитьРезультат()
        let кодИсхода: Int32 = постусловие ? ответ.код : (ответ.код == 0 ? 3 : ответ.код)
        try Файлы.записатьНовый(итог, кодировать(СохранённыйИсход(
            схема: "fum.исход-перехода.1", фаза: фаза, хэшПлана: план.отпечаток(),
            код: кодИсхода, объект: объект, пояснение: "exit=" + String(ответ.код) + "; постусловие=" + String(постусловие))))
        try требовать((кодИсхода == 0 || разрешёнКонфликт && кодИсхода == 1) &&
                       постусловие, "отказ/дрейф после эффекта; автоматического повтора нет")
    }
    func действие(_ вид: String, коммит: String, пояснение: String) throws -> ВнешнееДействие {
        try ВнешнееДействие(схема: "fum.действие-координатора-перехода.1",
            операция: план.задание.операция, хэшПлана: план.отпечаток(),
            владелец: план.задание.владелец, чат: план.задание.чат, вид: вид,
            ожидаемаяВетка: план.новаяВетка, ожидаемыйКоммит: коммит,
            новоеНазвание: вид == "переименовать-чат" ? план.названиеЧата : nil, пояснение: пояснение)
    }
    func результат(_ фаза: String, коммит: String, включён: Bool = false,
                   подготовлен: Bool = false, конфликты: [String] = [],
                   действие: ВнешнееДействие? = nil) -> РезультатПерехода {
        РезультатПерехода(схема: "fum.результат-перехода-ветки.1", фаза: фаза,
            коммит: коммит, кореньВключён: включён, слияниеПодготовлено: подготовлен,
            конфликты: конфликты, действиеКоординатора: действие, атомарностьЧатаИГит: false)
    }
    func переименоватьОснову() throws {
        try требовать(разрешеныЭффекты && блокировка >= 0, "читающий actor не разрешает эффекты")
        let фаза = try состояние()
        try требовать(фаза != "неизвестный-исход", "неизвестный исход; команда не повторена")
        try требовать(try гит.прочитать(["status", "--porcelain=v1", "--untracked-files=all"]).isEmpty, "дерево не чистое")
        try проверитьСервер(false)
        let задание = план.задание
        let текущаяВетка = try гит.прочитать(["symbolic-ref", "HEAD"])
        try требовать([задание.прежняяВетка, план.новаяВетка].contains(текущаяВетка), "чужая текущая ветка")
        do {
            if текущаяВетка == задание.прежняяВетка {
                try Планировщик.проверитьГраницу(задание, корень: план.выборКорня, гит: гит)
                try ИменаПерехода.проверитьКоллизии(план.новаяВетка,
                    существующие: try гит.ссылки().keys.filter { $0.hasPrefix("refs/heads/") })
            }
            try эффект("01-переименование", аргументы: ["branch", "-m", String(задание.прежняяВетка.dropFirst(11)), String(план.новаяВетка.dropFirst(11))],
                объект: задание.ожидаемыйКоммит, проверитьРезультат: {
                    let ссылки = try гит.ссылки()
                    let текущая = try гит.прочитать(["symbolic-ref", "HEAD"])
                    return ссылки[план.новаяВетка] == задание.ожидаемыйКоммит &&
                        ссылки[задание.прежняяВетка] == nil &&
                        текущая == план.новаяВетка
                })
        }
        try требовать(try гит.прочитать(["symbolic-ref", "HEAD"]) == план.новаяВетка,
                       "другая ветка после переименования")
        try проверитьСервер(true)
    }
    public func переименовать() throws -> РезультатПерехода {
        try переименоватьОснову()
        let текущий = try гит.прочитать(["rev-parse", "HEAD"])
        try требовать(текущий == план.задание.ожидаемыйКоммит, "неожиданный HEAD после rename")
        let включён = try кореньВключён(текущий)
        return результат("локальная-ветка-переименована", коммит: текущий, включён: включён,
            действие: try действие("продолжить-включение-корня", коммит: текущий,
                пояснение: "checkpoint: remote не публиковался; merge/check/review/Creator и чат ещё не приняты"))
    }
    public func сверить() throws -> РезультатПерехода {
        let фаза = try состояние()
        try проверитьСервер(false)
        let текущий = try гит.прочитать(["rev-parse", "HEAD"])
        let включён = try кореньВключён(текущий)
        return результат(фаза, коммит: текущий, включён: включён,
                         действие: try действие("сверить-сохранённые-намерения", коммит: текущий,
                             пояснение: "сам по себе отсутствующий remote не доказывает, что команда не передавалась"))
    }
    func кореньВключён(_ коммит: String) throws -> Bool {
        let ответ = try гит.вызвать(["merge-base", "--is-ancestor", план.выборКорня.коммит, коммит])
        try требовать([0, 1].contains(ответ.код), "не удалось проверить ancestry L")
        return ответ.код == 0
    }
}

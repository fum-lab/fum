"""Маска ограждённого Markdown сохраняет смещения исходного текста."""
import re


ОГРАДА = re.compile(r' {0,3}(`{3,}|~{3,})([^\r\n]*)(?:\r?\n|\Z)')


def маскировать(текст):
    """Вернуть маску и признак незакрытой ограды; исходник не изменяется."""
    if '```' not in текст and '~~~' not in текст:
        return текст, False
    ограда = None
    строки = []
    for совпадение_строки in re.finditer(r'[^\n]*(?:\n|\Z)', текст):
        строка = совпадение_строки.group()
        скрыть = ограда is not None
        совпадение = ОГРАДА.fullmatch(строка)
        if совпадение is not None:
            знаки, хвост = совпадение.group(1, 2)
            if ограда is None:
                if знаки[0] != '`' or '`' not in хвост:
                    ограда = знаки
                    скрыть = True
            elif знаки[0] == ограда[0] and len(знаки) >= len(ограда) and not хвост.strip(' \t'):
                ограда = None
        if скрыть:
            конец = len(строка.rstrip('\r\n'))
            строки.append(' ' * конец + строка[конец:])
        else:
            строки.append(строка)
    return ''.join(строки), ограда is not None

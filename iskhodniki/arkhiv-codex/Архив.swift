import Foundation
import Darwin
import КонтейнерНаблюдений

/// Синхронный единственный владелец; экземпляр намеренно не Sendable.
/// Общий flock удерживается на всём цикле, включая ротацию сегментов.
public final class АрхивКодекса {
    private let корень: URL
    private let сессия: String
    private let поколение: String
    private let операции: ФайловыеОперации
    private let порцийВСегменте: Int
    private let граница: (String) throws -> Void
    private var каталог: Int32 = -1
    private var сегмент: Сегмент?
    private var номер = 0
    private var записей = 0
    private var предыдущая = String(repeating: "0", count: 64)
    private var отказ = false
    private var идётОперация = false
    private var ошибкаЗавершения: (any Error)?
    private var зонд = ЗондСессии()
    public private(set) var сохранено: UInt64 = 0
    public private(set) var обработано: UInt64 = 0
    public private(set) var границаСтрок: UInt64 = 0
    public private(set) var подтверждённаяСессия: String?
    public var числоСегментов: Int { номер + 1 }
    public let пределПорции: Int

    public init(корень: URL, сессия: UUID, поколение: UUID,
                пределПорции: Int = 8 * 1_048_576, порцийВСегменте: Int = 4096,
                операции: ФайловыеОперации = .системные,
                восстановитьХвост: Bool = false,
                граница: @escaping (String) throws -> Void = { _ in }) throws {
        guard пределПорции > 0, пределПорции <= Пределы.объект,
              порцийВСегменте >= 2, порцийВСегменте <= Пределы.записи else {
            throw ОшибкаАрхиваКодекса.неверныйПредел
        }
        self.корень = корень; self.сессия = сессия.uuidString.lowercased()
        self.поколение = поколение.uuidString.lowercased()
        self.пределПорции = пределПорции; self.порцийВСегменте = порцийВСегменте
        self.операции = операции; self.граница = граница
        do {
            var родитель = try открытьПриватныйКаталог(корень.deletingLastPathComponent())
            do {
                if mkdirat(родитель, корень.lastPathComponent, 0o700) != 0 && errno != EEXIST {
                    throw ОшибкаКонтейнера.система(errno)
                }
                // EEXIST может быть результатом прежнего неизвестного parent-fsync.
                try операции.синхронизация(родитель)
                let дескриптор = родитель; родитель = -1
                try системноеЗакрытие(дескриптор)
            } catch { if родитель >= 0 { _ = Darwin.close(родитель) }; throw error }
            каталог = try открытьПриватныйКаталог(корень)
            var режимКорня = stat()
            guard fstat(каталог, &режимКорня) == 0, режимКорня.st_mode & 0o7777 == 0o700 else {
                throw ОшибкаАрхиваКодекса.небезопасныйПуть
            }
            guard flock(каталог, LOCK_EX | LOCK_NB) == 0 else {
                if errno == EWOULDBLOCK { throw ОшибкаКонтейнера.занят }
                throw ОшибкаКонтейнера.система(errno)
            }
            let количество = try посчитатьСегменты(каталог)
            if количество == 0 {
                try создатьСегмент()
            } else {
                for индекс in 0..<количество {
                    номер = индекс
                    var пустойПоследний = false
                    if восстановитьХвост && индекс == количество - 1 {
                        пустойПоследний = try пустойКаталог(путьСегмента(индекс))
                    }
                    // Только явное восстановление завершает последний пустой mkdir.
                    // Перед повтором устанавливается устойчивость его имени в корне.
                    if пустойПоследний { try операции.синхронизация(каталог) }
                    let открытый = try Сегмент(кореньДанных: путьСегмента(индекс), запись: true,
                                               создать: пустойПоследний, операции: операции)
                    сегмент = открытый; записей = 0
                    for квитанция in открытый.записи {
                        try проверить(квитанция, данные: открытый.извлечь(квитанция.описание.идентификатор))
                        записей += 1
                    }
                    if открытый.естьХвост {
                        guard восстановитьХвост, индекс == количество - 1 else {
                            throw ОшибкаКонтейнера.неполныйХвост
                        }
                    }
                    guard записей > 0 || (восстановитьХвост && индекс == количество - 1) else {
                        throw ОшибкаКонтейнера.неполныйХвост
                    }
                    // Проверенные committed записи синхронизируются заново без повторного append.
                    try открытый.восстановитьХвост()
                    if записей == 0 { try записать("сегмент", данные: Data(), ротация: false) }
                    if индекс < количество - 1 { try открытый.завершить(); сегмент = nil }
                }
            }
        } catch { try? завершить(); throw error }
    }

    deinit { try? завершить() }

    private func путьСегмента(_ индекс: Int) -> URL {
        корень.appendingPathComponent(String(format: "%08d", индекс), isDirectory: true)
    }

    func доступ() throws {
        guard каталог >= 0, сегмент != nil, !отказ, !идётОперация else { throw ОшибкаАрхиваКодекса.закрыт }
    }

    func начатьОперацию() throws { try доступ(); идётОперация = true }
    func закончитьОперацию() { идётОперация = false }

    private func создатьСегмент() throws {
        guard mkdirat(каталог, String(format: "%08d", номер), 0o700) == 0 else {
            throw ОшибкаКонтейнера.система(errno)
        }
        try операции.синхронизация(каталог)
        сегмент = try Сегмент(кореньДанных: путьСегмента(номер), запись: true, операции: операции)
        записей = 0
        try записать("сегмент", данные: Data(), ротация: false)
    }

    private func ротировать() throws {
        try граница("до-ротации")
        try сегмент?.завершить(); сегмент = nil
        guard номер < Int(Int32.max) else { throw ОшибкаАрхиваКодекса.неверныйПредел }
        номер += 1
        try создатьСегмент()
        try граница("после-ротации")
    }

    private func метаданные(_ вид: String, данные: Data) throws -> МетаданныеПорции {
        guard UInt64(данные.count) <= UInt64.max - сохранено else { throw ОшибкаАрхиваКодекса.неверныйПредел }
        return МетаданныеПорции(версия: 1, вид: вид, сессия: сессия,
            подтверждённаяСессия: вид == "сессия" ? зонд.найденная : подтверждённаяСессия,
            поколение: поколение, начало: сохранено, конец: сохранено + UInt64(данные.count),
            границаХранимыхСтрок: последняяГраницаСтроки(данные, начало: сохранено, прежняя: границаСтрок),
            обработано: вид == "проекция" ? границаСтрок : обработано,
            хэшБайтов: вычислитьХэшБайтов(данные), предыдущаяКвитанция: предыдущая)
    }

    private func записать(_ вид: String, данные: Data, ротация: Bool = true) throws {
        if ротация && записей >= порцийВСегменте { try ротировать() }
        func добавить() throws {
            let запись = try метаданные(вид, данные: данные)
            let байты = try кодироватьМетаданные(запись)
            let описание = ОписаниеНаблюдения(идентификатор: "\(номер):\(записей)",
                тип: "fum.raw-codex.1", источник: поколение, время: "не-заявлено", спецификация: байты)
            guard let сегмент else { throw ОшибкаАрхиваКодекса.закрыт }
            let квитанция = try сегмент.добавить(описание, данные: данные)
            try проверить(квитанция, данные: данные)
            записей += 1
        }
        do { try добавить() }
        catch ОшибкаКонтейнера.предел where ротация {
            try ротировать()
            try добавить()
        }
    }

    private func проверить(_ квитанция: Квитанция, данные: Data) throws {
        let описание = квитанция.описание
        let запись = try JSONDecoder().decode(МетаданныеПорции.self, from: описание.спецификация)
        let ожидаемая = try метаданные(запись.вид, данные: данные)
        guard try кодироватьМетаданные(запись) == описание.спецификация,
              описание.тип == "fum.raw-codex.1", описание.версияСхемы == 1,
              описание.источник == поколение, описание.время == "не-заявлено",
              описание.идентификатор == "\(номер):\(записей)",
              квитанция.размер == данные.count, квитанция.хэш == вычислитьХэшБайтов(данные),
              запись.версия == 1, запись.сессия == сессия, запись.поколение == поколение,
              запись.предыдущаяКвитанция == предыдущая, запись == ожидаемая,
              ["сегмент", "raw", "сессия", "проекция"].contains(запись.вид),
              (записей == 0) == (запись.вид == "сегмент"),
              (запись.вид == "raw" ? !данные.isEmpty : данные.isEmpty) else {
            throw ОшибкаАрхиваКодекса.повреждение
        }
        if запись.вид == "raw" {
            guard данные.count <= Пределы.объект else { throw ОшибкаАрхиваКодекса.неверныйПредел }
            // JSON только после append+fsync либо при replay устойчивого RAW.
            зонд.принять(данные)
        } else if запись.вид == "сессия" {
            guard зонд.найденная != nil else { throw ОшибкаАрхиваКодекса.повреждение }
        }
        сохранено = запись.конец; границаСтрок = запись.границаХранимыхСтрок
        обработано = запись.обработано; подтверждённаяСессия = запись.подтверждённаяСессия
        предыдущая = вычислитьХэшБайтов(описание.спецификация)
    }

    public func принять(_ данные: Data, смещение: UInt64) throws {
        try начатьОперацию(); defer { закончитьОперацию() }
        try принятьЧасть(данные, смещение: смещение)
    }

    func принятьЧасть(_ данные: Data, смещение: UInt64) throws {
        guard данные.count <= пределПорции else { throw ОшибкаАрхиваКодекса.неверныйПредел }
        guard смещение <= сохранено else { throw ОшибкаАрхиваКодекса.источникИзменён }
        if смещение < сохранено {
            guard UInt64(данные.count) <= сохранено - смещение else { throw ОшибкаАрхиваКодекса.источникИзменён }
            var позиция: UInt64 = 0, сравнено = 0
            let конец = смещение + UInt64(данные.count)
            try обойтиИсходныеБайты { прежние in
                let следующий = позиция + UInt64(прежние.count)
                defer { позиция = следующий }
                let от = max(позиция, смещение), до = min(следующий, конец)
                if от < до {
                    let число = Int(до - от)
                    guard прежние.subdata(in: Int(от - позиция)..<Int(до - позиция)) ==
                        данные.subdata(in: (данные.startIndex + сравнено)..<(данные.startIndex + сравнено + число)) else {
                        throw ОшибкаАрхиваКодекса.источникИзменён
                    }
                    сравнено += число
                }
            }
            return
        }
        guard !данные.isEmpty else { return }
        do {
            try записать("raw", данные: данные)
            try подтвердитьСессию()
        } catch { отказ = true; throw error }
    }

    func подтвердитьСессию() throws {
        if let найденная = зонд.найденная, найденная != подтверждённаяСессия {
            try записать("сессия", данные: Data())
        }
        if зонд.конфликт || (подтверждённаяСессия != nil && подтверждённаяСессия != сессия) {
            throw ОшибкаАрхиваКодекса.сессияНеСовпала
        }
    }

    /// Точные порции без синтаксической проекции и без исходного файла.
    public func восстановить(_ приём: (Data) throws -> Void) throws {
        try начатьОперацию(); defer { закончитьОперацию() }
        try обойтиИсходныеБайты { данные in try приём(данные) }
    }

    func обойтиИсходныеБайты(_ приём: (Data) throws -> Void) throws {
        for индекс in 0...номер {
            let текущий: Сегмент
            if индекс == номер, let сегмент { текущий = сегмент }
            else { текущий = try Сегмент(кореньДанных: путьСегмента(индекс), запись: false, создать: false) }
            do {
                for квитанция in текущий.записи {
                    let запись = try JSONDecoder().decode(МетаданныеПорции.self, from: квитанция.описание.спецификация)
                    if запись.вид == "raw" { try приём(текущий.извлечь(квитанция.описание.идентификатор)) }
                }
                if индекс != номер { try текущий.завершить() }
            } catch { if индекс != номер { текущий.закрыть() }; throw error }
        }
    }

    /// Callback получает части ещё не обработанного LF-префикса для существующей проекции.
    /// Его ошибка не подтверждает обработку. Хвост без LF остаётся только в RAW.
    public func проецировать(_ приём: (Data) throws -> Void) throws {
        try начатьОперацию(); defer { закончитьОперацию() }
        let начало = обработано, конец = границаСтрок
        guard начало < конец else { return }
        var позиция: UInt64 = 0
        try обойтиИсходныеБайты { данные in
            let следующий = позиция + UInt64(данные.count)
            defer { позиция = следующий }
            let от = max(позиция, начало), до = min(следующий, конец)
            if от < до { try приём(данные.subdata(in: Int(от - позиция)..<Int(до - позиция))) }
        }
        do { try записать("проекция", данные: Data()) }
        catch { отказ = true; throw error }
    }

    public func завершить() throws {
        guard !идётОперация else { throw ОшибкаАрхиваКодекса.закрыт }
        if let ошибкаЗавершения { throw ошибкаЗавершения }
        var ошибка: (any Error)?
        do { try сегмент?.завершить() } catch { ошибка = error }
        сегмент = nil
        if каталог >= 0 {
            let дескриптор = каталог; каталог = -1
            if flock(дескриптор, LOCK_UN) != 0 { ошибка = ошибка ?? ОшибкаКонтейнера.система(errno) }
            do { try операции.закрытие(дескриптор) } catch { ошибка = ошибка ?? error }
        }
        отказ = true
        if let ошибка { ошибкаЗавершения = ошибка; throw ошибка }
    }
}

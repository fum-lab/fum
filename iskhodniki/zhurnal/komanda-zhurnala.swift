import Foundation
import ОсноваЗапуска

struct ОтветПланаЗаписи: Codable, Sendable {
    var схема = "fum.ответ-плана-локальной-записи.1"
    var план: ПланЗаписи
}

public struct ОтказКомандыЖурнала: Error, Sendable {
    public let код: String
    public func представление() throws -> Data {
        struct Ответ: Encodable {
            let схема = "fum.отказ-локальной-записи.1"
            let состояние = "отказ"
            let код: String
            let файловыйЭффект = "После начала установки возможен сохранённый эффект; проверьте тот же путь без очистки и нового ID"
        }
        return try ПредставлениеЗапуска.байты(Ответ(код: код), читаемо: true)
    }
}

public enum КомандаЖурнала {
    public static let справка = """
    fuma журнал план --корень <физический-корень> --вход <JSON>
    fuma журнал применить --корень <тот-же-корень> --вход <тот-же-JSON> --план <сохранённый-ответ-плана>
    Необязательный --оператор <JSON> выбирает явные байты определения вместо встроенного ресурса.
    Вход содержит явные ROOT/писателя/стадию/номер, время, область, происхождение и содержание.
    Существующий каталог <область>/zhurnal готовится владельцем заранее; plan не пишет файлов.
    Применение создаёт один файл O_EXCL. Совпадение возвращает «наблюдена» без новой записи.
    Неполный файл сохраняется; повтор его не дописывает. Автоматической очистки и нового ID нет.
    Наблюдение байтов после сбоя не подтверждает прежний fsync или приёмку ROOT.
    """

    public static func выполнить(_ аргументы: [String]) throws -> Data {
        do { return try исполнить(аргументы) }
        catch let ошибка as ОтказЖурнала { throw ОтказКомандыЖурнала(код: ошибка.rawValue) }
        catch { throw ОтказКомандыЖурнала(код: ОтказЖурнала.вход.rawValue) }
    }

    private static func исполнить(_ аргументы: [String]) throws -> Data {
        if аргументы == ["помощь"] { return Data((справка + "\n").utf8) }
        guard let действие = аргументы.first, ["план", "применить"].contains(действие),
              (аргументы.count - 1).isMultiple(of: 2) else { throw ОтказЖурнала.вход }
        var поля: [String: String] = [:]
        for номер in stride(from: 1, to: аргументы.count, by: 2) {
            let ключ = аргументы[номер]
            guard ["--корень", "--вход", "--оператор", "--план"].contains(ключ), поля[ключ] == nil,
                  !аргументы[номер + 1].isEmpty else { throw ОтказЖурнала.вход }
            поля[ключ] = аргументы[номер + 1]
        }
        guard let корень = поля["--корень"], let путьВхода = поля["--вход"] else { throw ОтказЖурнала.вход }
        let вход = try Data(contentsOf: URL(fileURLWithPath: путьВхода))
        let оператор = try поля["--оператор"].map { try Data(contentsOf: URL(fileURLWithPath: $0)) }
            ?? ПланировщикЗаписи.оператор()
        if действие == "план" {
            guard поля["--план"] == nil else { throw ОтказЖурнала.вход }
            // Только область нужна наблюдателю; полный закрытый разбор выполняет engine перед планом.
            let данные = try JSONDecoder().decode(ВходЗаписи.self, from: вход)
            let цель = try ГраницаЦели.наблюдать(корень: корень, область: данные.область)
            let план = try ПланировщикЗаписи.построить(вход, оператор: оператор, цель: цель)
            return try ПредставлениеЗапуска.байты(ОтветПланаЗаписи(план: план), читаемо: true)
        }
        guard let путьПлана = поля["--план"] else { throw ОтказЖурнала.вход }
        let ответ = try JSONDecoder().decode(ОтветПланаЗаписи.self,
            from: Data(contentsOf: URL(fileURLWithPath: путьПлана)))
        guard ответ.схема == "fum.ответ-плана-локальной-записи.1" else { throw ОтказЖурнала.вход }
        let результат = try ФайловыйАдаптер.применить(ответ.план, вход: вход, оператор: оператор, корень: корень)
        return try ПредставлениеЗапуска.байты(результат, читаемо: true)
    }
}

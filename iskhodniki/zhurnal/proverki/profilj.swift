import Foundation
import Testing
@testable import ЖурналУзла
import ОсноваЗапуска

struct ПрофильЖурнала: Codable {
    struct Вызов: Codable {
        var сообщений: Int
        var повтор: Int
        var хэшВхода: String
        var хэшОператора: String
        var замеры: [ЗамерЗаписи]
        enum CodingKeys: String, CodingKey {
            case сообщений = "сообщений"
            case повтор = "повтор"
            case хэшВхода = "входSHA256"
            case хэшОператора = "операторSHA256"
            case замеры = "замеры"
        }
    }
    var схема = "fum.профиль-конечной-локальной-записи.1"
    var условия = "Debug Swift6; два конечных входа, три повтора; существующие временные цели. Без обхода Git и всего репозитория. Установка исключает повторное чистое формирование; внешний процесс и сборка учтены отдельно"
    var вызовы: [Вызов]
}

@Test(.enabled(if: ProcessInfo.processInfo.environment["FUM_ПРОФИЛЬ_ЖУРНАЛА"] != nil))
func профильКонечногоВхода() throws {
    guard let выход = ProcessInfo.processInfo.environment["FUM_ПРОФИЛЬ_ЖУРНАЛА"] else { throw ОтказЖурнала.вход }
    var вызовы: [ПрофильЖурнала.Вызов] = []
    for размер in [1, 16] {
        var вход = примерВхода()
        вход.сообщения = Array(repeating: вход.сообщения[0], count: размер)
        let данные = try ПредставлениеЗапуска.байты(вход, читаемо: true)
        let оператор = try ПланировщикЗаписи.оператор()
        for повтор in 1...3 {
            let корень = try временнаяЦель()
            defer { try? FileManager.default.removeItem(at: корень) }
            let цель = try ГраницаЦели.наблюдать(корень: корень.path, область: вход.область)
            var замеры: [ЗамерЗаписи] = []
            let план = try ПланировщикЗаписи.построить(данные, оператор: оператор, цель: цель, профиль: { замеры.append($0) })
            let безПрофиля = try ПланировщикЗаписи.построить(данные, оператор: оператор, цель: цель)
            #expect(план == безПрофиля)
            let результат = try ФайловыйАдаптер.применить(план, вход: данные, оператор: оператор, корень: корень.path,
                профиль: { замеры.append($0) })
            #expect(результат.вид == .установлена)
            #expect(замеры.count == 3)
            вызовы.append(ПрофильЖурнала.Вызов(сообщений: размер, повтор: повтор, хэшВхода: хэш(данные),
                хэшОператора: хэш(оператор), замеры: замеры))
        }
    }
    try ПредставлениеЗапуска.байты(ПрофильЖурнала(вызовы: вызовы), читаемо: true)
        .write(to: URL(fileURLWithPath: выход), options: [.withoutOverwriting])
}

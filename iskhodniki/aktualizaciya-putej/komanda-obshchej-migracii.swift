import Foundation

struct ВходОбщейМиграции: Codable, Sendable {
    var корень: String
    var основа: ОсноваОбщейМиграции
    var переносимыеКорни: [String]
    var удаляемаяПроекция: String?
}

struct СухойПланОбщейМиграции: Codable, Sendable {
    var схема = "fum.сухой-план-общей-миграции-путей.1"
    var инвентарь: ИнвентарьОбщейМиграции
    var планСостава: ПланОбщейМиграции
    var охватСсылок = "полный канонический корпус и адаптеры ещё не проверены"
    var исполнение = "версионирование общего исполнителя и журнала ещё не выполнено"
    var применениеРазрешено = false
}

enum КомандаОбщейМиграции {
    static func построить(_ вход: ВходОбщейМиграции) async throws -> СухойПланОбщейМиграции {
        let снятая = try await ЧитательОбщейМиграции.снять(корень: URL(fileURLWithPath: вход.корень), ожидаемаяОснова: вход.основа,
            переносимыеКорни: вход.переносимыеКорни, удаляемаяПроекция: вход.удаляемаяПроекция)
        let план = try ОбщийПланировщикПутей.построить(основа: вход.основа, ожидаемаяОснова: вход.основа,
            узлы: снятая.узлы, корни: снятая.инвентарь.корни)
        return .init(инвентарь: снятая.инвентарь, планСостава: план)
    }
}

#if ФУМ_ОБЩИЙ_ПЛАН_КОМАНДА
@main struct ЗапускОбщегоПлана {
    static func main() async {
        do {
            let данные = try FileHandle.standardInput.readToEnd() ?? Data()
            let вход = try JSONDecoder().decode(ВходОбщейМиграции.self, from: данные)
            let план = try await КомандаОбщейМиграции.построить(вход)
            try FileHandle.standardOutput.write(contentsOf: байтыПлана(план))
        } catch {
            try? FileHandle.standardError.write(contentsOf: Data("Общий сухой план: \(error)\n".utf8))
            exit(2)
        }
    }
}
#endif

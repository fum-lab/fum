/// Чистое ядро: не читает Git/FS/App, не перемещает W и не выдаёт полномочий на эффект.
public enum ЯдроАдресаАгента {
    public static let версия = "fum.логический-адрес-агента.1"

    public static func план(адрес: ЛогическийАдресАгента, контекст: КонтекстАдресаАгента,
                           ожидалось: СнимокАдресаАгента, инвентарь: [СнимокАдресаАгента]) throws -> ПланАдресаАгента {
        guard !адрес.каталог.isEmpty, адрес.каталог.count <= 64,
              ([адрес.репозиторий.владелецФорка, адрес.репозиторий.репозиторий] + адрес.каталог).allSatisfy(компонент),
              непрозрачный(адрес.репозиторий.origin), непрозрачный(адрес.версияВхода), шестнадцатеричный(адрес.входSHA256, 64),
              шестнадцатеричный(контекст.источникЯдраSHA256, 64), шестнадцатеричный(контекст.инвентарьSHA256, 64), абсолютный(контекст.база),
              шестнадцатеричный(контекст.принятыйM, 40), шестнадцатеричный(контекст.проверяющийSHA256, 64), шестнадцатеричный(контекст.refsSHA256, 64),
              контекст.refs.count <= 16384, контекст.refs.allSatisfy(refВерна),
              Set(контекст.refs.map { Data($0.utf8) }).count == контекст.refs.count,
              UUID(uuidString: контекст.корневаяЗадача) != nil, UUID(uuidString: контекст.владелец) != nil,
              сессияВерна(контекст.сессия), непрозрачный(ожидалось.идентификатор),
              шестнадцатеричный(ожидалось.HEAD, 40), шестнадцатеричный(ожидалось.индексSHA256, 64),
              абсолютный(ожидалось.физическийW), абсолютный(ожидалось.областьЗаписи),
              вложен(ожидалось.областьЗаписи, в: ожидалось.физическийW),
              try одинаковы(адрес.репозиторий, ожидалось.репозиторий), инвентарь.count <= 4096 else {
            throw ОшибкаАдресаАгента.неверныйВход("Опоры адреса, версии, сессии или снимка")
        }
        let короткийRef = ([адрес.репозиторий.владелецФорка, адрес.репозиторий.репозиторий] + адрес.каталог + ["master"]).joined(separator: "/")
        let целевойRef = "refs/heads/" + короткийRef
        guard целевойRef.utf8.count <= 1024 else { throw ОшибкаАдресаАгента.неверныйВход("Длина ref") }
        let целевойW = контекст.база + "/" + короткийRef
        guard целевойW.utf8.count <= 4096, точно(контекст.назначение.полныйRef, целевойRef),
              точно(контекст.назначение.физическийW, целевойW) else {
            throw ОшибкаАдресаАгента.неверныйВход("Наблюдение назначения не относится к вычисленным ref/W")
        }
        let сортированный = инвентарь.sorted { порядокПутей($0.идентификатор, $1.идентификатор) }
        guard Set(сортированный.map(\.идентификатор)).count == сортированный.count,
              сортированный.allSatisfy({ непрозрачный($0.идентификатор) && абсолютный($0.физическийW) }),
              let собственный = сортированный.first(where: { $0.идентификатор == ожидалось.идентификатор }),
              try одинаковы(собственный, ожидалось) else { throw ОшибкаАдресаАгента.неверныйВход("Инвентарь не содержит точный собственный снимок") }
        var препятствия: [ПрепятствиеАдресаАгента] = []
        func добавить(_ п: ПрепятствиеАдресаАгента) { if !препятствия.contains(п) { препятствия.append(п) } }
        if контекст.инвентарьПолон != .да || контекст.refsПолны != .да { добавить(.неполныйИнвентарь) }
        let назначение = контекст.назначение
        if назначение.родителиПроверены == .нет { добавить(.непроверенныеРодителиЦели) }
        if назначение.родителиПроверены == .неизвестно { добавить(.неизвестныеФакты) }
        if !точно(целевойW, ожидалось.физическийW) {
            if назначение.путьСвободен == .нет { добавить(.путьНазначенияЗанят) }
            if назначение.путьСвободен == .неизвестно { добавить(.неизвестныеФакты) }
        }
        if !точно(целевойW, ожидалось.физическийW) || ожидалось.полныйRef.map({ !точно($0, целевойRef) }) != false {
            if назначение.переходAppПоддержан == .нет { добавить(.неподдерживаемыйПереходApp) }
            if назначение.переходAppПоддержан == .неизвестно { добавить(.неизвестныеФакты) }
        }
        let с = ожидалось.свойства
        let исключения = [с.основное, с.внешняяЗависимость, с.историческое]
        if исключения.contains(.да) { добавить(.исключённоеДерево) }
        if исключения.contains(.неизвестно) { добавить(.неизвестныеФакты) }
        for (факт, отказ) in [(с.чистое, ПрепятствиеАдресаАгента.грязноеДерево), (с.неактивное, .активноеДерево),
                             (с.разблокировано, .блокировкаДерева), (с.физическийПутьПроверен, .непроверенныйПуть),
                             (с.безСимволическихСсылок, .непроверенныйПуть), (с.безВложеннойЗависимости, .вложеннаяЗависимость)] {
            if факт == .нет { добавить(отказ) }; if факт == .неизвестно { добавить(.неизвестныеФакты) }
        }
        if ожидалось.владелец == nil { добавить(.неизвестныеФакты) }
        else if ожидалось.владелец != контекст.владелец { добавить(.чужойВладелец) }
        if let привязка = ожидалось.привязка {
            if !сессияВерна(привязка) || привязка.управляемоеДерево == .неизвестно { добавить(.неизвестныеФакты) }
            if !(try одинаковы(привязка, контекст.сессия)) || привязка.управляемоеДерево == .нет
                || !точно(привязка.рабочаяОбласть, ожидалось.областьЗаписи) { добавить(.чужаяСессия) }
        } else { добавить(.неизвестныеФакты) }
        if !вложен(ожидалось.физическийW, в: контекст.база) || точно(ожидалось.физическийW, контекст.база) { добавить(.внеБазы) }
        if let ref = ожидалось.полныйRef {
            guard refВерна(ref) else { throw ОшибкаАдресаАгента.неверныйВход("Неверный исходный ref") }
            if !контекст.refs.contains(where: { точно($0, ref) }) { добавить(.неполныйИнвентарь) }
            if !точно(целевойRef, ref), пересекаются(целевойRef, ref) { добавить(.конфликтRef) }
        } else { добавить(.detachedHEAD) }
        if !точно(целевойW, ожидалось.физическийW), пересекаются(целевойW, ожидалось.физическийW) {
            добавить(.конфликтW)
        }
        for ref in контекст.refs where ожидалось.полныйRef.map({ !точно($0, ref) }) != false {
            if пересекаются(целевойRef, ref) { добавить(.конфликтRef) }
        }
        for запись in сортированный where запись.идентификатор != ожидалось.идентификатор {
            if пересекаются(целевойW, запись.физическийW) { добавить(.конфликтW) }
            if ИменаПутей.ключКоллизии(запись.репозиторий.владелецФорка + "/" + запись.репозиторий.репозиторий)
                == ИменаПутей.ключКоллизии(адрес.репозиторий.владелецФорка + "/" + адрес.репозиторий.репозиторий), let ref = запись.полныйRef {
                guard refВерна(ref) else { throw ОшибкаАдресаАгента.неверныйВход("Неверный ref инвентаря") }
                if пересекаются(целевойRef, ref) { добавить(.конфликтRef) }
            }
        }
        if ИменаПутей.ключКоллизии(целевойW) == ИменаПутей.ключКоллизии(ожидалось.физическийW), !точно(целевойW, ожидалось.физическийW) {
            добавить(.толькоРегистрИлиНормализация)
        }
        var цель = ожидалось
        цель.полныйRef = целевойRef; цель.физическийW = целевойW
        let суффикс = ожидалось.областьЗаписи.utf8.dropFirst(ожидалось.физическийW.utf8.count)
        цель.областьЗаписи = целевойW + String(decoding: суффикс, as: UTF8.self)
        цель.привязка?.рабочаяОбласть = цель.областьЗаписи
        препятствия.sort { $0.rawValue < $1.rawValue }
        let состояние: СостояниеАдресаАгента
        if препятствия.contains(.исключённоеДерево) { состояние = .исключено }
        else if препятствия.contains(.неизвестныеФакты) || препятствия.contains(.неполныйИнвентарь) { состояние = .неизвестно }
        else if !препятствия.isEmpty { состояние = .заблокировано }
        else { состояние = try одинаковы(цель, ожидалось) ? .согласовано : .готовоКНамерению }
        let материал = МатериалПланаАдреса(версия: версия, адрес: адрес, контекст: контекст, ожидалось: ожидалось,
            инвентарь: сортированный, цель: цель, препятствия: препятствия, состояние: состояние)
        return ПланАдресаАгента(материал: материал, отпечаток: try отпечаток(материал))
    }

    public static func проверитьПлан(_ план: ПланАдресаАгента) throws {
        guard план.материал.версия == версия else { throw ОшибкаАдресаАгента.изменённыйПлан }
        let новый = try self.план(адрес: план.адрес, контекст: план.контекст, ожидалось: план.ожидалось, инвентарь: план.материал.инвентарь)
        guard try одинаковы(новый, план) else { throw ОшибкаАдресаАгента.изменённыйПлан }
    }

    public static func намерение(план: ПланАдресаАгента, свежийПлан: ПланАдресаАгента, идентификатор: String,
                                 наблюдение: СнимокАдресаАгента, история: ИсторияПопытокАдресаАгента,
                                 допуск: ПроверенныйДопускАдресаАгента, времяСекундUTC: Int64) throws -> НамерениеАдресаАгента {
        try проверитьСвежесть(план, свежийПлан: свежийПлан)
        try сверитьДопуск(допуск, план: план, времяСекундUTC: времяСекундUTC)
        let прежниеПопытки = история.намерения
        guard план.можноПодготовитьНамерение, UUID(uuidString: идентификатор) != nil,
              история.полна == .да, шестнадцатеричный(история.источникSHA256, 64), история.источникSHA256 == допуск.материал.историяSHA256,
              прежниеПопытки.count <= 4096,
              прежниеПопытки.allSatisfy({ $0.версия == версия && UUID(uuidString: $0.идентификатор) != nil && шестнадцатеричный($0.отпечатокПлана, 64) }),
              !прежниеПопытки.contains(where: { $0.идентификатор == идентификатор || $0.отпечатокПлана == план.отпечаток }),
              try одинаковы(наблюдение, план.ожидалось) else { throw ОшибкаАдресаАгента.недопустимыйПереход }
        return .init(идентификатор: идентификатор, отпечатокПлана: план.отпечаток,
                     допускSHA256: допуск.утверждённыйSHA256, историяSHA256: история.источникSHA256)
    }

    public static func проверитьНамерение(_ намерение: НамерениеАдресаАгента, план: ПланАдресаАгента) throws {
        try проверитьПлан(план)
        guard намерение.версия == версия, UUID(uuidString: намерение.идентификатор) != nil,
              шестнадцатеричный(намерение.допускSHA256, 64), шестнадцатеричный(намерение.историяSHA256, 64),
              намерение.отпечатокПлана == план.отпечаток, план.можноПодготовитьНамерение else {
            throw ОшибкаАдресаАгента.недопустимыйПереход
        }
    }

    public static func восстановить(план: ПланАдресаАгента, намерение: НамерениеАдресаАгента,
                                    исход: ИсходАдресаАгента?, наблюдение: СнимокАдресаАгента) throws -> ВосстановлениеАдресаАгента {
        try проверитьНамерение(намерение, план: план)
        guard let исход, исход.идентификаторНамерения == намерение.идентификатор,
              исход.отпечатокПлана == план.отпечаток,
              let квитанция = исход.квитанцияSHA256, шестнадцатеричный(квитанция, 64), let после = исход.наблюдение,
              try одинаковы(после, наблюдение) else { return .init(состояние: .неизвестно) }
        switch исход.вид {
        case .применено:
            return .init(состояние: try одинаковы(наблюдение, план.цель) ? .подтверждено : .неизвестно)
        case .безЭффекта:
            return .init(состояние: try одинаковы(наблюдение, план.ожидалось) ? .завершеноБезЭффекта : .неизвестно)
        case .неизвестно: return .init(состояние: .неизвестно)
        }
    }

    fileprivate static func отпечаток<T: Encodable>(_ значение: T) throws -> String { try хэшПутей(байтыПлана(значение)) }
    fileprivate static func одинаковы<T: Encodable>(_ л: T, _ п: T) throws -> Bool { try отпечаток(л) == отпечаток(п) }
    private static func точно(_ л: String, _ п: String) -> Bool { л.utf8.elementsEqual(п.utf8) }
    private static func непрозрачный(_ с: String) -> Bool { !с.isEmpty && с.utf8.count <= 1024 && !с.unicodeScalars.contains { $0.value < 32 || $0.value == 127 } }
    fileprivate static func шестнадцатеричный(_ с: String, _ длина: Int) -> Bool { с.utf8.count == длина && с.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) } }
    private static func компонент(_ с: String) -> Bool {
        guard !с.isEmpty, с.utf8.count <= 255, !с.hasSuffix(".lock"), !["package.swift", "agents.md", "skill.md"].contains(с) else { return false }
        var разделитель = true
        for б in с.utf8 {
            if (97...122).contains(б) || (48...57).contains(б) { разделитель = false }
            else if (б == 45 || б == 46), !разделитель { разделитель = true }
            else { return false }
        }
        return !разделитель
    }
    private static func абсолютный(_ с: String) -> Bool {
        guard с.hasPrefix("/"), с.utf8.count <= 4096 else { return false }
        return (try? ИменаПутей.проверитьПуть(String(с.dropFirst()))) != nil
    }
    private static func refВерна(_ с: String) -> Bool {
        guard с.hasPrefix("refs/heads/"), !с.contains(".."), !с.contains("@{"),
              !с.utf8.contains(where: { [32, 126, 94, 58, 63, 42, 91].contains($0) }) else { return false }
        let части = с.split(separator: "/", omittingEmptySubsequences: false)
        return (try? ИменаПутей.проверитьПуть(с)) != nil && части.allSatisfy { !$0.hasPrefix(".") && !$0.hasSuffix(".") && !$0.hasSuffix(".lock") }
    }
    private static func сессияВерна(_ с: ПривязкаСессииАгента) -> Bool {
        UUID(uuidString: с.threadID) != nil && непрозрачный(с.hostID) && непрозрачный(с.clientID)
            && (с.projectID.map(непрозрачный) ?? true) && абсолютный(с.рабочаяОбласть)
    }
    private static func вложен(_ путь: String, в родитель: String) -> Bool { ИменаПутей.вложен(путь, в: родитель) }
    private static func пересекаются(_ л: String, _ п: String) -> Bool {
        let а = ИменаПутей.ключКоллизии(л), б = ИменаПутей.ключКоллизии(п)
        return а == б || а.starts(with: б + Data([47])) || б.starts(with: а + Data([47]))
    }
}

extension ЯдроАдресаАгента {
    public static let версияДопуска = "fum.допуск-эффекта-адреса-агента.1"

    public static func опоры(план: ПланАдресаАгента, источникПолномочия: String,
                             полномочиеSHA256: String) throws -> ОпорыДопускаАдресаАгента {
        try проверитьПлан(план)
        guard !источникПолномочия.isEmpty, источникПолномочия.utf8.count <= 1024,
              шестнадцатеричный(полномочиеSHA256, 64), let ref = план.ожидалось.полныйRef else {
            throw ОшибкаАдресаАгента.недействительныйДопуск
        }
        return .init(источникПолномочия: источникПолномочия, полномочиеSHA256: полномочиеSHA256,
            принятыйM: план.контекст.принятыйM, источникЯдраSHA256: план.контекст.источникЯдраSHA256,
            инвентарьSHA256: план.контекст.инвентарьSHA256, refsSHA256: план.контекст.refsSHA256,
            проверяющийSHA256: план.контекст.проверяющийSHA256, корневаяЗадача: план.контекст.корневаяЗадача,
            корень: план.ожидалось.физическийW, полныйRef: ref, HEAD: план.ожидалось.HEAD,
            владелец: план.контекст.владелец, индексSHA256: план.ожидалось.индексSHA256)
    }

    /// Доверенный pin и опоры берутся из принятого ROOT/M/checker-свидетельства.
    /// Вычисление caller-ом нового «утверждённого» SHA из этих же bytes не является допуском.
    public static func проверитьДопуск(байты: Data, утверждённыйSHA256: String, опоры: ОпорыДопускаАдресаАгента,
                                       план: ПланАдресаАгента, времяСекундUTC: Int64) throws -> ПроверенныйДопускАдресаАгента {
        guard !байты.isEmpty, байты.count <= 65536, шестнадцатеричный(утверждённыйSHA256, 64),
              хэшПутей(байты) == утверждённыйSHA256 else { throw ОшибкаАдресаАгента.недействительныйДопуск }
        let материал = try JSONDecoder().decode(ДопускЭффектаАдресаАгента.self, from: байты)
        guard try одинаковы(материал.опоры, опоры) else { throw ОшибкаАдресаАгента.недействительныйДопуск }
        let допуск = ПроверенныйДопускАдресаАгента(материал: материал, утверждённыйSHA256: утверждённыйSHA256)
        try сверитьДопуск(допуск, план: план, времяСекундUTC: времяСекундUTC)
        return допуск
    }

    /// Адаптер вызывает эту проверку ВНУТРИ guarded effect path с текущим временем и fresh RO-планом,
    /// удерживая single-writer/custody lock. Затем атомарно расходует попытку до единственного transport.
    /// Полный opaque receipt сохраняется до разбора. UNKNOWN не разрешает повтор transport.
    public static func проверитьПередЭффектом(допуск: ПроверенныйДопускАдресаАгента, план: ПланАдресаАгента,
                                             свежийПлан: ПланАдресаАгента, намерение: НамерениеАдресаАгента,
                                             команда: Data, времяСекундUTC: Int64) throws {
        try проверитьСвежесть(план, свежийПлан: свежийПлан)
        try сверитьДопуск(допуск, план: план, времяСекундUTC: времяСекундUTC)
        try проверитьНамерение(намерение, план: план)
        guard !команда.isEmpty, команда.count <= 65536, хэшПутей(команда) == допуск.командаSHA256,
              намерение.допускSHA256 == допуск.утверждённыйSHA256,
              намерение.историяSHA256 == допуск.материал.историяSHA256 else {
            throw ОшибкаАдресаАгента.недействительныйДопуск
        }
    }

    fileprivate static func проверитьСвежесть(_ план: ПланАдресаАгента, свежийПлан: ПланАдресаАгента) throws {
        try проверитьПлан(план); try проверитьПлан(свежийПлан)
        guard try одинаковы(план, свежийПлан) else { throw ОшибкаАдресаАгента.изменённыйПлан }
    }

    fileprivate static func сверитьДопуск(_ допуск: ПроверенныйДопускАдресаАгента, план: ПланАдресаАгента,
                                         времяСекундUTC: Int64) throws {
        try проверитьПлан(план)
        let д = допуск.материал
        let ожидаемые = try опоры(план: план, источникПолномочия: д.опоры.источникПолномочия, полномочиеSHA256: д.опоры.полномочиеSHA256)
        guard д.версия == версияДопуска, план.можноПодготовитьНамерение, try одинаковы(д.опоры, ожидаемые),
              д.планSHA256 == план.отпечаток, шестнадцатеричный(д.командаSHA256, 64), шестнадцатеричный(д.историяSHA256, 64),
              шестнадцатеричный(д.квитанцияМаршрутаSHA256, 64), д.выданоСекундUTC >= 0,
              времяСекундUTC >= д.выданоСекундUTC, времяСекундUTC < д.истекаетСекундUTC else {
            throw ОшибкаАдресаАгента.недействительныйДопуск
        }
        if д.маршрут == .пройден {
            guard д.исключениеROOT == nil else { throw ОшибкаАдресаАгента.недействительныйДопуск }
            return
        }
        guard let и = д.исключениеROOT, !д.причинаМаршрута.isEmpty, д.причинаМаршрута.utf8.count <= 4096,
              и.корневаяЗадача == ожидаемые.корневаяЗадача,
              и.причинаОтказа.utf8.elementsEqual(д.причинаМаршрута.utf8),
              и.квитанцияОтказаSHA256 == д.квитанцияМаршрутаSHA256,
              и.опорыSHA256 == (try отпечаток(ожидаемые)), и.планSHA256 == д.планSHA256,
              и.командаSHA256 == д.командаSHA256 else { throw ОшибкаАдресаАгента.недействительныйДопуск }
    }
}


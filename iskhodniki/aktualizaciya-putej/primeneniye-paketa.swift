import Foundation
import Darwin
import КонтейнерНаблюдений

// Синхронная часть удерживает lock журнала до квитанции. Между эффектами нет await.
// Подтверждённый префикс — история прямых шагов; откат его не стирает.
final class ПрименениеПакета {
    private let корень: URL
    private let план: ПланПакета
    private let байты: Data
    private let основаХранилища: URL?
    private let неисправность: ((String, Int) throws -> Void)?
    private let профиль: ПрофильПакета?
    private let операцииЖурнала: ФайловыеОперации

    init(корень: URL, план: ПланПакета, байты: Data, основаХранилища: URL?,
        неисправность: ((String, Int) throws -> Void)?, профиль: ПрофильПакета? = nil,
        операцииЖурнала: ФайловыеОперации = .системные) {
        self.корень = корень; self.план = план; self.байты = байты
        self.основаХранилища = основаХранилища; self.неисправность = неисправность
        self.профиль = профиль
        self.операцииЖурнала = операцииЖурнала
    }

    func выполнить() throws -> КвитанцияПакета {
        guard let журнал = try ЖурналПакета.открыть(корень: корень, план: план, байты: байты,
            основаДляПроверки: основаХранилища, создать: true, операции: операцииЖурнала) else {
            throw ОтказПакета.условие("не-создан-журнал-пакета")
        }
        if !журнал.новый {
            guard let квитанция = try журнал.квитанция() else {
                throw ОтказПакета.условие("существует-незавершённое-намерение-эффект-не-повторён")
            }
            return квитанция
        }
        let состояние = try СостояниеПримененияПакета(корень: корень, план: план, профиль: профиль)
        try состояние.проверить(глубоко: true)
        try журнал.записать("намерение", байты)
        let решение = try ПравилаПакета.выполнить(ВходРешенияПакета(
            ограды: ОградыПакета(план_совпадает: true, снимок_совпадает: true,
                индекс_совпадает: true, пути_разрешены: true),
            число_переносов: 9, состояние_намерения: "сохранено"))
        try журнал.записать("решение-FUMA", решение.наблюдение)
        guard решение.решение.допустить_применение else {
            throw ОтказПакета.условие("FUMA-не-разрешил-пакет")
        }
        var неизвестныйПереход = false
        do {
            for номер in 1...14 {
                try неисправность?("до-намерения", номер)
                try состояние.проверить(глубоко: false)
                try журнал.записать("шаг-\(номер)-намерение", описание(номер, префикс: номер - 1))
                try неисправность?("после-намерения", номер)
                try состояние.проверить(глубоко: false)
                // Даже отказ Git после запуска может иметь эффект. До проверки префикса
                // такой переход не даёт полномочий на автоматический обратный шаг.
                неизвестныйПереход = true
                try состояние.изменить(номер, обратно: false, хэшПлана: журнал.хэшПлана,
                    послеПримитива: { try self.неисправность?("после-примитива", номер) })
                try состояние.проверить(глубоко: false)
                неизвестныйПереход = false
                try неисправность?("после-эффекта", номер)
                try журнал.записать("шаг-\(номер)-подтверждение", описание(номер, префикс: номер))
            }
            try состояние.проверить(глубоко: true)
            let итог = КвитанцияПакета(план_sha256: журнал.хэшПлана, исход: "завершено",
                подтверждённый_префикс: try журнал.подтверждённыйПрефикс,
                наблюдённый_префикс: 14, причина: nil)
            return try сохранить(итог, журнал)
        } catch {
            // Append мог записать неизвестный хвост. Этот instance закрыт контейнером;
            // новое открытие/UUID здесь не используется и эффект не повторяется.
            guard журнал.доступен else { throw ОтказПакета.условие("журнал-отказал-исход-неизвестен") }
            let причина = String(describing: error)
            if неизвестныйПереход {
                return try сохранить(КвитанцияПакета(план_sha256: журнал.хэшПлана,
                    исход: "неизвестно", подтверждённый_префикс: журнал.подтверждённыйПрефикс,
                    наблюдённый_префикс: nil, причина: причина), журнал)
            }
            do {
                try состояние.проверить(глубоко: true)
                try журнал.записать("откат-намерение", описание(0, префикс: состояние.префикс))
                while состояние.префикс > 0 {
                    let номер = состояние.префикс
                    try неисправность?("до-отката", номер)
                    try состояние.проверить(глубоко: false)
                    try журнал.записать("откат-\(номер)-намерение", описание(номер, префикс: номер))
                    try состояние.проверить(глубоко: false)
                    try состояние.изменить(номер, обратно: true, хэшПлана: журнал.хэшПлана)
                    try состояние.проверить(глубоко: false)
                    try журнал.записать("откат-\(номер)-подтверждение", описание(номер, префикс: номер - 1))
                }
                try состояние.проверить(глубоко: true)
                return try сохранить(КвитанцияПакета(план_sha256: журнал.хэшПлана,
                    исход: "откат-проверен", подтверждённый_префикс: журнал.подтверждённыйПрефикс,
                    наблюдённый_префикс: 0, причина: причина), журнал)
            } catch {
                guard журнал.доступен else { throw ОтказПакета.условие("журнал-отказал-при-откате-исход-неизвестен") }
                let наблюдённый: Int?
                do {
                    try состояние.проверить(глубоко: true)
                    наблюдённый = (1...13).contains(состояние.префикс) ? состояние.префикс : nil
                }
                catch { наблюдённый = nil }
                return try сохранить(КвитанцияПакета(план_sha256: журнал.хэшПлана,
                    исход: наблюдённый == nil ? "неизвестно" : "частичный",
                    подтверждённый_префикс: журнал.подтверждённыйПрефикс,
                    наблюдённый_префикс: наблюдённый,
                    причина: причина + "; отказ-отката: " + String(describing: error)), журнал)
            }
        }
    }

    private func описание(_ шаг: Int, префикс: Int) throws -> Data {
        struct Шаг: Codable { var шаг: Int; var префикс: Int; var план_sha256: String }
        return try байтыПлана(Шаг(шаг: шаг, префикс: префикс, план_sha256: хэшПутей(байты)))
    }

    private func сохранить(_ квитанция: КвитанцияПакета, _ журнал: ЖурналПакета) throws -> КвитанцияПакета {
        try журнал.записать("итог", байтыПлана(квитанция))
        guard let прочитанная = try журнал.квитанция(), прочитанная == квитанция else {
            throw ОтказПакета.условие("квитанция-не-подтверждена-чтением")
        }
        return прочитанная
    }
}

private final class СостояниеПримененияПакета {
    private let корень: URL
    private let план: ПланПакета
    private let исходныйИндекс: [ЭлементИндексаПакета]
    private let профиль: ПрофильПакета?
    private var файлы: [Data: ФайлПакета] = [:]
    private var каталоги: [Data: КаталогПакета] = [:]
    private var документы: Set<Data>
    private(set) var префикс = 0

    init(корень: URL, план: ПланПакета, профиль: ПрофильПакета?) throws {
        self.корень = корень; self.план = план
        self.профиль = профиль
        исходныйИндекс = try ЭлементИндексаПакета.разобрать(план.индекс)
        документы = Set(план.документы.map { Data($0.путь.utf8) })
        for файл in план.документы + план.исходники { файлы[Data(файл.путь.utf8)] = файл }
        for каталог in план.каталоги { каталоги[Data(каталог.путь.utf8)] = каталог }
    }

    func проверить(глубоко: Bool) throws {
        let начало = DispatchTime.now().uptimeNanoseconds
        defer { профиль?.добавить(глубоко ? "ограды-префикса-с-байтами" : "ограды-префикса-с-метаданными", от: начало) }
        try ПакетПутей.проверитьПоручение(корень, план.поручение)
        guard try ПакетПутей.пространство(корень) == план.пространство else {
            throw ОтказПакета.условие("дрейф-namespace-при-применении")
        }
        var индекс = исходныйИндекс
        for перенос in план.переносы.prefix(min(префикс, 9)) {
            guard let номер = индекс.firstIndex(where: { $0.путь == Data(перенос.исходный.utf8) }) else {
                throw ОтказПакета.условие("нет-исходной-stage0-записи")
            }
            индекс[номер].путь = Data(перенос.целевой.utf8)
        }
        guard try ЧитательПакета.гит(корень, ["ls-files", "--stage", "-z"]) == ЭлементИндексаПакета.байты(индекс),
              try Set(ЧитательПакета.инвентарь(корень).map { Data($0.utf8) }) == документы else {
            throw ОтказПакета.условие("дрейф-stage0-или-Markdown-при-применении")
        }
        let читатель = try ЧитательПакета(корень)
        for ключ in файлы.keys.sorted(by: { $0.lexicographicallyPrecedes($1) }) {
            let ожидаемый = файлы[ключ]!
            let текущий: ФайлПакета
            if глубоко { текущий = try читатель.прочитать(ожидаемый.путь).0 }
            else { текущий = try читатель.метаданные(ожидаемый.путь, хэш: ожидаемый.sha256) }
            guard try байтыПлана(текущий) == байтыПлана(ожидаемый) else {
                throw ОтказПакета.условие("дрейф-файла-при-применении")
            }
        }
        let текущие = try читатель.снимокКаталогов()
        let ожидаемые = каталоги.values.sorted { порядокПутей($0.путь, $1.путь) }
        guard try байтыПлана(текущие) == байтыПлана(ожидаемые) else {
            throw ОтказПакета.условие("дрейф-каталога-при-применении")
        }
    }

    func изменить(_ номер: Int, обратно: Bool, хэшПлана: String,
        послеПримитива: (() throws -> Void)? = nil) throws {
        let начало = DispatchTime.now().uptimeNanoseconds
        defer { профиль?.добавить(обратно ? "обратный-эффект" : "прямой-эффект", от: начало) }
        guard номер == (обратно ? префикс : префикс + 1), (1...14).contains(номер) else {
            throw ОтказПакета.условие("неверный-переход-префикса")
        }
        if номер <= 9 {
            let перенос = план.переносы[номер - 1]
            let откуда = обратно ? перенос.целевой : перенос.исходный
            let куда = обратно ? перенос.исходный : перенос.целевой
            let старыйКлюч = Data(откуда.utf8), новыйКлюч = Data(куда.utf8)
            guard let прежде = файлы[старыйКлюч] else { throw ОтказПакета.условие("нет-собственного-исходника") }
            _ = try ЧитательПакета.гит(корень, ["mv", "--", откуда, куда])
            try послеПримитива?()
            try синхронизироватьПеренос(куда)
            let после = try ЧитательПакета(корень).прочитать(куда).0
            guard после.sha256 == перенос.sha256, после.режим == прежде.режим,
                  после.устройство == прежде.устройство, после.инод == прежде.инод,
                  после.размер == прежде.размер else { throw ОтказПакета.условие("перенос-изменил-байты-mode-или-inode") }
            let родитель = (откуда as NSString).deletingLastPathComponent
            let ключКаталога = Data(родитель.utf8)
            guard var каталог = каталоги[ключКаталога] else { throw ОтказПакета.условие("нет-собственного-родителя") }
            let имя = Data((откуда as NSString).lastPathComponent.precomposedStringWithCanonicalMapping.utf8)
            guard let место = каталог.имена.firstIndex(where: {
                Data(String(decoding: $0, as: UTF8.self).precomposedStringWithCanonicalMapping.utf8) == имя
            }) else { throw ОтказПакета.условие("нет-прежнего-имени") }
            каталог.имена.remove(at: место)
            // На APFS имя кириллицей может иметь NFD. Читаем фактическое d_name,
            // проверив прежний inode/mode каталога и точный ожидаемый набор имён.
            let новыйКаталог = try ЧитательПакета(корень).каталог(родитель).1
            let новоеИмя = Data((куда as NSString).lastPathComponent.precomposedStringWithCanonicalMapping.utf8)
            let кандидаты = новыйКаталог.имена.filter {
                Data(String(decoding: $0, as: UTF8.self).precomposedStringWithCanonicalMapping.utf8) == новоеИмя
            }
            guard кандидаты.count == 1 else { throw ОтказПакета.условие("не-одно-новое-имя") }
            каталог.имена.append(кандидаты[0]); каталог.имена.sort { $0.lexicographicallyPrecedes($1) }
            guard try байтыПлана(каталог) == байтыПлана(новыйКаталог) else {
                throw ОтказПакета.условие("дрейф-родителя-после-переноса")
            }
            каталоги[ключКаталога] = каталог
            файлы.removeValue(forKey: старыйКлюч); файлы[новыйКлюч] = после
            if документы.remove(старыйКлюч) != nil { документы.insert(новыйКлюч) }
        } else {
            let правка = план.правки[номер - 10]
            let ключ = Data(правка.путь.utf8)
            guard let прежде = файлы[ключ] else { throw ОтказПакета.условие("нет-собственной-правки") }
            let данные = обратно ? правка.прежде : правка.после
            try заменить(правка.путь, данные, прежде, хэшПлана + "-\(номер)" + (обратно ? "-otkat" : ""))
            try послеПримитива?()
            let после = try ЧитательПакета(корень).прочитать(правка.путь).0
            guard после.sha256 == хэшПутей(данные), после.режим == правка.режим else {
                throw ОтказПакета.условие("правка-не-подтверждена")
            }
            файлы[ключ] = после
        }
        префикс += обратно ? -1 : 1
    }

    private func заменить(_ путь: String, _ данные: Data, _ прежний: ФайлПакета, _ метка: String) throws {
        let читатель = try ЧитательПакета(корень)
        let (родитель, _) = try читатель.каталог((путь as NSString).deletingLastPathComponent)
        let имя = (путь as NSString).lastPathComponent
        let временное = ".fum-paket-" + метка + ".tmp"
        let дескриптор = openat(родитель, временное, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        guard дескриптор >= 0 else { throw ОтказПакета.условие("backup-или-временный-файл-уже-занят") }
        defer { close(дескриптор) }
        // При отказе временный файл сохраняется. Его наличие закрывает следующий
        // переход и остаётся наблюдаемым остатком, а не удаляется вслепую.
        try FileHandle(fileDescriptor: дескриптор, closeOnDealloc: false).write(contentsOf: данные)
        guard fchmod(дескриптор, mode_t(прежний.режим)) == 0, fsync(дескриптор) == 0 else {
            throw ОтказПакета.условие("подготовленная-правка-не-синхронизирована")
        }
        var атрибуты = stat()
        guard fstatat(родитель, имя, &атрибуты, AT_SYMLINK_NOFOLLOW) == 0,
              атрибуты.st_mode & S_IFMT == S_IFREG, атрибуты.st_nlink == 1, атрибуты.st_uid == getuid(),
              атрибуты.st_ino == прежний.инод, UInt64(атрибуты.st_dev) == прежний.устройство,
              UInt32(атрибуты.st_mode & 0o7777) == прежний.режим,
              атрибуты.st_size == прежний.размер,
              Int64(атрибуты.st_mtimespec.tv_sec) == прежний.изменение_секунды,
              Int64(атрибуты.st_mtimespec.tv_nsec) == прежний.изменение_наносекунды,
              Int64(атрибуты.st_ctimespec.tv_sec) == прежний.метаданные_секунды,
              Int64(атрибуты.st_ctimespec.tv_nsec) == прежний.метаданные_наносекунды else {
            throw ОтказПакета.условие("дрейф-перед-установкой-правки")
        }
        guard renameat(родитель, временное, родитель, имя) == 0, fsync(родитель) == 0 else {
            throw ОтказПакета.условие("правка-не-установлена-или-не-синхронизирована")
        }
    }

    private func синхронизироватьПеренос(_ путь: String) throws {
        let читатель = try ЧитательПакета(корень)
        let (родитель, _) = try читатель.каталог((путь as NSString).deletingLastPathComponent)
        let файл = openat(родитель, (путь as NSString).lastPathComponent, O_RDONLY | O_NOFOLLOW | O_CLOEXEC)
        guard файл >= 0 else { throw ОтказПакета.условие("перенесённый-файл-не-открыт") }
        defer { close(файл) }
        let адресGit = try ЧитательПакета.физический(URL(fileURLWithPath:
            ЧитательПакета.строкаГит(корень, ["rev-parse", "--absolute-git-dir"])))
        let git = open(адресGit.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard git >= 0 else { throw ОтказПакета.условие("Git-admin-не-открыт") }
        defer { close(git) }
        let индекс = openat(git, "index", O_RDONLY | O_NOFOLLOW | O_CLOEXEC)
        guard индекс >= 0 else { throw ОтказПакета.условие("индекс-не-открыт-для-синхронизации") }
        defer { close(индекс) }
        guard fsync(файл) == 0, fsync(родитель) == 0, fsync(индекс) == 0, fsync(git) == 0 else {
            throw ОтказПакета.условие("перенос-не-синхронизирован")
        }
    }
}

import Foundation
import Darwin

struct ВходПланаПутей: Codable, Sendable {
    var схема = "fum.запрос-актуализации-путей.1"
    var контекст: КонтекстПутей
    var области: [String]
}

enum КомандаПутей {
    static func построить(корень: URL, вход: ВходПланаПутей, хэшВхода: String) async throws -> ПланПутей {
        try await измерить(корень: корень, вход: вход, хэшВхода: хэшВхода).0
    }

    private static func наносекунды(_ начало: ContinuousClock.Instant) -> Int64 {
        let части = начало.duration(to: ContinuousClock.now).components
        return части.seconds * 1_000_000_000 + части.attoseconds / 1_000_000_000
    }

    static func измерить(корень: URL, вход: ВходПланаПутей, хэшВхода: String) async throws -> (ПланПутей, [String: Int64]) {
        guard вход.схема == "fum.запрос-актуализации-путей.1", !вход.контекст.корень.hasPrefix("/") else {
            throw ОшибкаПутей.отказ("Неизвестный вход или машинный адрес вместо идентичности корня")
        }
        var профиль: [String: Int64] = [:]
        let начало = ContinuousClock.now
        let чтение = try ЧитательПутей.снять(корень: корень, области: вход.области)
        профиль["чтение-снимка"] = наносекунды(начало)
        let началоИмен = ContinuousClock.now
        let карта = try await ТранслитераторПутей().отобразить(чтение.снимок.записи)
        профиль["имена"] = наносекунды(началоИмен)
        let началоПлана = ContinuousClock.now
        var контекст = вход.контекст
        let сырыеВетки = try ЧитательПутей.гит(корень, ["for-each-ref", "--format=%(refname)", "refs/heads/"]).0
        guard let ветки = String(data: сырыеВетки, encoding: .utf8) else { throw ОшибкаПутей.отказ("НеUTF8 ref") }
        контекст.ветки = ветки.split(separator: "\n").map(String.init)
        var план = try ПостроительПланаПутей.построить(чтение.снимок, отображения: карта, контекст: контекст,
            хэшОтображения: хэшПутей(байтыПлана(карта)), соседи: чтение.соседи)
        план.вход_sha256 = хэшВхода
        план.выбранные_области = вход.области
        план.ссылки = АнализСсылокПутей.собрать(чтение.тексты)
        if план.ссылки.contains(where: { $0.состояние != "историческое/дословное — сохранено" }) {
            план.препятствия.append(ПрепятствиеПути(код: "обновление-ссылок-не-реализовано", пути: []))
        }
        профиль["план-и-кандидаты-ссылок"] = наносекунды(началоПлана)
        let началоСверки = ContinuousClock.now
        let поздний = try ЧитательПутей.снять(корень: корень, области: вход.области)
        guard try поздний.снимок.подпись() == чтение.снимок.подпись() else { throw ОшибкаПутей.отказ("Дрейф за время построения плана") }
        профиль["независимая-поздняя-сверка"] = наносекунды(началоСверки)
        профиль["полный-путь"] = наносекунды(начало)
        return (план, профиль)
    }

    static func сверить(сохранённые: Data, ожидаемыйХэш: String, текущий: ПланПутей) throws {
        guard хэшПутей(сохранённые) == ожидаемыйХэш else { throw ОшибкаПутей.отказ("Изменены сырые байты выбранного плана") }
        let план = try JSONDecoder().decode(ПланПутей.self, from: сохранённые)
        guard try байтыПлана(план) == сохранённые, try байтыПлана(текущий) == сохранённые,
              !план.применение_разрешено else { throw ОшибкаПутей.отказ("Дрейф полного плана или его входов") }
    }

    static func выполнить(_ аргументы: [String]) async throws -> Data {
        if аргументы.first == "имя" {
            guard аргументы.count == 3, аргументы[1] == "--компонент", !аргументы[2].isEmpty else {
                throw ОшибкаПутей.отказ("Нужны имя --компонент <один-логический-компонент>")
            }
            let результат = try await ПубличныйФасадИмён.канонизировать(аргументы[2])
            return try байтыПлана(результат)
        }
        if let действие = аргументы.first, ["план-файла", "применить-файл"].contains(действие) {
            return try ПереименованиеФайла.выполнить(аргументы)
        }
        guard let действие = аргументы.first, ["план", "diff", "сверить", "профиль"].contains(действие) else {
            throw ОшибкаПутей.отказ("Нужны план|diff|сверить|профиль, --корень и --вход; для сверки --план и --sha256-плана")
        }
        var параметры: [String: String] = [:]
        var номер = 1
        while номер < аргументы.count {
            let имя = аргументы[номер]
            guard ["--корень", "--вход", "--план", "--sha256-плана"].contains(имя), номер + 1 < аргументы.count,
                  параметры[имя] == nil else { throw ОшибкаПутей.отказ("Неизвестный или повторный параметр") }
            параметры[имя] = аргументы[номер + 1]; номер += 2
        }
        guard let адрес = параметры["--корень"], let файл = параметры["--вход"] else { throw ОшибкаПутей.отказ("Не заданы корень и вход") }
        let корень = URL(fileURLWithPath: адрес).standardizedFileURL
        let сырые = try Data(contentsOf: URL(fileURLWithPath: файл))
        var вход = try JSONDecoder().decode(ВходПланаПутей.self, from: сырые)
        вход.контекст.писатель = ProcessInfo.processInfo.environment["CODEX_THREAD_ID"] ?? ""
        let хэшВхода = хэшПутей(сырые)
        let результат = try await измерить(корень: корень, вход: вход, хэшВхода: хэшВхода)
        guard try Data(contentsOf: URL(fileURLWithPath: файл)) == сырые else { throw ОшибкаПутей.отказ("Дрейф входного описания") }
        if действие == "сверить" {
            guard let путь = параметры["--план"], let хэш = параметры["--sha256-плана"] else { throw ОшибкаПутей.отказ("Нужен независимо выбранный план и SHA256") }
            try сверить(сохранённые: Data(contentsOf: URL(fileURLWithPath: путь)), ожидаемыйХэш: хэш, текущий: результат.0)
            return try байтыПлана(["схема": "fum.сверка-плана-путей.1", "исход": "полный план и входы совпали", "применение": "запрещено"])
        }
        if действие == "diff" {
            return Data(результат.0.отображения.filter { Data($0.исходный.utf8) != Data($0.целевой.utf8) }
                .map { "--- a/\($0.исходный)\n+++ b/\($0.целевой)\n" }.joined().utf8)
        }
        if действие == "профиль" {
            var наблюдения = [результат.1]
            let ожидалось = try байтыПлана(результат.0)
            for _ in 0..<2 {
                let следующее = try await измерить(корень: корень, вход: вход, хэшВхода: хэшВхода)
                guard try байтыПлана(следующее.0) == ожидалось else { throw ОшибкаПутей.отказ("Дрейф между повторами профиля") }
                наблюдения.append(следующее.1)
            }
            struct Профиль: Encodable {
                var схема = "fum.профиль-актуализации-путей.1"
                var план_sha256: String
                var наблюдения_нс: [[String: Int64]]
                var условия = "три последовательных повтора одного процесса; первый включает подготовку таблицы; кэш ОС не очищен; вложенные интервалы не складываются"
            }
            return try байтыПлана(Профиль(план_sha256: хэшПутей(ожидалось), наблюдения_нс: наблюдения))
        }
        return try байтыПлана(результат.0)
    }
}

#if ФУМ_КОМАНДА_ПУТЕЙ
@main enum ЗапускПутей {
    static func main() async {
        do { FileHandle.standardOutput.write(try await КомандаПутей.выполнить(Array(CommandLine.arguments.dropFirst()))) }
        catch { FileHandle.standardError.write(Data(("Отказ команды: \(error)\n").utf8)); exit(2) }
    }
}
#endif

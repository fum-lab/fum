struct РезультатУстановкиЛокальногоВхода: Codable, Equatable, Sendable {
    var схема = "fum.результат-установки-локального-входа-агента.1"
    let исход: ИсходУстановкиЛокальногоВхода
    let путь: String
    let хэшSHA256: String
    let числоБайтов: Int
}

enum ОшибкаУстановщикаЛокальногоВхода: Error, CustomStringConvertible, Equatable, Sendable {
    case существующаяЦельОтличается
    case существующаяЦельСимволическаяСсылка
    case существующаяЦельНеОбычныйФайл
    case системная(операция: String, код: Int32)
    case неизвестныйИсходПослеПубликации(операция: String, код: Int32?)
    case неизвестныйОстатокВременногоФайла(операция: String, код: Int32?)

    var description: String {
        switch self {
        case .существующаяЦельОтличается:
            "Существующий AGENTS.md отличается; замена запрещена"
        case .существующаяЦельСимволическаяСсылка:
            "Существующий AGENTS.md является символической ссылкой; переход и замена запрещены"
        case .существующаяЦельНеОбычныйФайл:
            "Существующий AGENTS.md не является обычным файлом; замена запрещена"
        case .системная(let операция, let код):
            "Системный отказ до публикации: \(операция), errno=\(код)"
        case .неизвестныйИсходПослеПубликации(let операция, let код):
            if let код {
                "Исход публикации неизвестен: \(операция), errno=\(код); повтор без сверки запрещён"
            } else {
                "Исход публикации неизвестен: \(операция); повтор без сверки запрещён"
            }
        case .неизвестныйОстатокВременногоФайла(let операция, let код):
            if let код {
                "Остаток временного файла неизвестен: \(операция), errno=\(код); повтор без сверки запрещён"
            } else {
                "Остаток временного файла неизвестен: \(операция); повтор без сверки запрещён"
            }
        }
    }
}

enum УстановщикЛокальногоВходаАгента {
    private static let имяЦели = "AGENTS.md"
    private static let префиксВременногоФайла = ".AGENTS.md.fum-"

    private enum СостояниеЦели {
        case отсутствует
        case совпадает
        case отличается
        case символическаяСсылка
        case неОбычныйФайл
    }

    static func установить(
        описание: ОписаниеЛокальногоВходаАгента,
        кореньРепозитория: URL
    ) throws -> РезультатУстановкиЛокальногоВхода {
        let корень = кореньРепозитория.standardizedFileURL.resolvingSymlinksInPath()
        let каталог = корень.appendingPathComponent(описание.путьКаталога, isDirectory: true)
        let содержимое = try ЛокальныйВходАгента.сформировать(
            описание: описание,
            кореньРепозитория: корень,
            каталогАгента: каталог
        )
        let путьЦели = описание.путьКаталога + "/" + имяЦели
        guard описание.областьЗаписи.contains(путьЦели) else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "цель отсутствует в области записи описания", код: EPERM
            )
        }
        let ожидаемыеБайты = Data(содержимое.utf8)
        let ожидаемыйХэш = SHA256.hash(data: ожидаемыеБайты)
            .map { String(format: "%02x", $0) }.joined()
        let каталогFD = try открытьКаталог(
            корень: корень,
            относительныйПуть: описание.путьКаталога
        )
        defer { _ = Darwin.close(каталогFD) }

        switch try состояниеЦели(каталогFD: каталогFD, ожидаемыеБайты: ожидаемыеБайты) {
        case .совпадает:
            return результат(.ужеСовпадает, путь: путьЦели,
                             хэш: ожидаемыйХэш, байты: ожидаемыеБайты.count)
        case .отличается:
            throw ОшибкаУстановщикаЛокальногоВхода.существующаяЦельОтличается
        case .символическаяСсылка:
            throw ОшибкаУстановщикаЛокальногоВхода.существующаяЦельСимволическаяСсылка
        case .неОбычныйФайл:
            throw ОшибкаУстановщикаЛокальногоВхода.существующаяЦельНеОбычныйФайл
        case .отсутствует:
            break
        }

        let временноеИмя = try подготовитьВременныйФайл(
            каталогFD: каталогFD,
            байты: ожидаемыеБайты
        )
        return try опубликовать(
            временноеИмя: временноеИмя,
            каталогFD: каталогFD,
            ожидаемыеБайты: ожидаемыеБайты,
            путьЦели: путьЦели,
            ожидаемыйХэш: ожидаемыйХэш
        )
    }

    private static func результат(
        _ исход: ИсходУстановкиЛокальногоВхода,
        путь: String,
        хэш: String,
        байты: Int
    ) -> РезультатУстановкиЛокальногоВхода {
        РезультатУстановкиЛокальногоВхода(
            исход: исход,
            путь: путь,
            хэшSHA256: хэш,
            числоБайтов: байты
        )
    }

    private static func опубликовать(
        временноеИмя: String,
        каталогFD: Int32,
        ожидаемыеБайты: Data,
        путьЦели: String,
        ожидаемыйХэш: String
    ) throws -> РезультатУстановкиЛокальногоВхода {
        let итогСвязи = linkat(каталогFD, временноеИмя, каталогFD, имяЦели, 0)
        if итогСвязи == 0 {
            guard unlinkat(каталогFD, временноеИмя, 0) == 0 else {
                throw ОшибкаУстановщикаЛокальногоВхода.неизвестныйИсходПослеПубликации(
                    операция: "удаление имени временного файла", код: errno
                )
            }
            do {
                try синхронизировать(каталогFD, операция: "fsync каталога после публикации")
                guard case .совпадает = try состояниеЦели(
                    каталогFD: каталогFD,
                    ожидаемыеБайты: ожидаемыеБайты
                ) else {
                    throw ОшибкаУстановщикаЛокальногоВхода
                        .неизвестныйИсходПослеПубликации(
                            операция: "точное чтение AGENTS.md после публикации", код: nil
                        )
                }
            } catch let ошибка as ОшибкаУстановщикаЛокальногоВхода {
                if case .неизвестныйИсходПослеПубликации = ошибка { throw ошибка }
                throw ОшибкаУстановщикаЛокальногоВхода.неизвестныйИсходПослеПубликации(
                    операция: "сверка AGENTS.md после публикации", код: системныйКод(ошибка)
                )
            } catch {
                throw ОшибкаУстановщикаЛокальногоВхода.неизвестныйИсходПослеПубликации(
                    операция: "сверка AGENTS.md после публикации", код: nil
                )
            }
            return результат(.создан, путь: путьЦели,
                             хэш: ожидаемыйХэш, байты: ожидаемыеБайты.count)
        }

        let кодСвязи = errno
        if кодСвязи == EEXIST {
            try очиститьВременныйФайл(
                каталогFD: каталогFD,
                имя: временноеИмя,
                контекст: "после EEXIST"
            )
            switch try состояниеЦели(каталогFD: каталогFD, ожидаемыеБайты: ожидаемыеБайты) {
            case .совпадает:
                return результат(.совпалПослеКонкурирующейПубликации, путь: путьЦели,
                                 хэш: ожидаемыйХэш, байты: ожидаемыеБайты.count)
            case .отличается:
                throw ОшибкаУстановщикаЛокальногоВхода.существующаяЦельОтличается
            case .символическаяСсылка:
                throw ОшибкаУстановщикаЛокальногоВхода.существующаяЦельСимволическаяСсылка
            case .неОбычныйФайл:
                throw ОшибкаУстановщикаЛокальногоВхода.существующаяЦельНеОбычныйФайл
            case .отсутствует:
                throw ОшибкаУстановщикаЛокальногоВхода.системная(
                    операция: "конкурирующая цель исчезла после EEXIST", код: EAGAIN
                )
            }
        }

        if кодСвязи == EINTR {
            let кодОчистки = unlinkat(каталогFD, временноеИмя, 0) == 0 ? nil : errno
            throw ОшибкаУстановщикаЛокальногоВхода.неизвестныйИсходПослеПубликации(
                операция: кодОчистки == nil
                    ? "linkat был прерван; состояние AGENTS.md требует внешней сверки"
                    : "linkat был прерван, а очистка временного имени не подтверждена",
                код: кодОчистки ?? кодСвязи
            )
        }

        try очиститьВременныйФайл(
            каталогFD: каталогFD,
            имя: временноеИмя,
            контекст: "после отказа linkat errno=\(кодСвязи)"
        )
        throw ОшибкаУстановщикаЛокальногоВхода.системная(
            операция: "исключительная публикация linkat", код: кодСвязи
        )
    }

    private static func открытьКаталог(корень: URL, относительныйПуть: String) throws -> Int32 {
        var сведенияПути = stat()
        guard lstat(корень.path, &сведенияПути) == 0 else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "lstat корня checkout", код: errno
            )
        }
        guard (сведенияПути.st_mode & S_IFMT) == S_IFDIR else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "корень checkout не является обычным каталогом", код: ENOTDIR
            )
        }
        var текущийFD = open(корень.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard текущийFD >= 0 else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "open корня checkout без перехода по ссылке", код: errno
            )
        }
        var открытыеСведения = stat()
        guard fstat(текущийFD, &открытыеСведения) == 0 else {
            let код = errno
            _ = Darwin.close(текущийFD)
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "fstat корня checkout", код: код
            )
        }
        guard открытыеСведения.st_dev == сведенияПути.st_dev,
              открытыеСведения.st_ino == сведенияПути.st_ino else {
            _ = Darwin.close(текущийFD)
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "корень checkout изменился между lstat и open", код: EAGAIN
            )
        }

        for компонент in относительныйПуть.split(separator: "/") {
            let следующийFD = openat(
                текущийFD,
                String(компонент),
                O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC
            )
            let кодОткрытия = errno
            _ = Darwin.close(текущийFD)
            guard следующийFD >= 0 else {
                throw ОшибкаУстановщикаЛокальногоВхода.системная(
                    операция: "openat компонента каталога \(компонент)", код: кодОткрытия
                )
            }
            текущийFD = следующийFD
        }
        return текущийFD
    }

    private static func состояниеЦели(
        каталогFD: Int32,
        ожидаемыеБайты: Data
    ) throws -> СостояниеЦели {
        var сведенияИмени = stat()
        guard fstatat(каталогFD, имяЦели, &сведенияИмени, AT_SYMLINK_NOFOLLOW) == 0 else {
            let код = errno
            if код == ENOENT { return .отсутствует }
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "fstatat AGENTS.md без перехода по ссылке", код: код
            )
        }
        let тип = сведенияИмени.st_mode & S_IFMT
        if тип == S_IFLNK { return .символическаяСсылка }
        guard тип == S_IFREG else { return .неОбычныйФайл }

        let файлFD = openat(
            каталогFD,
            имяЦели,
            O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC
        )
        guard файлFD >= 0 else {
            let код = errno
            if код == ELOOP { return .символическаяСсылка }
            if код == ENOENT { return .отсутствует }
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "openat AGENTS.md для ограниченного чтения", код: код
            )
        }
        defer { _ = Darwin.close(файлFD) }

        var сведенияФайла = stat()
        guard fstat(файлFD, &сведенияФайла) == 0 else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "fstat открытого AGENTS.md", код: errno
            )
        }
        guard (сведенияФайла.st_mode & S_IFMT) == S_IFREG else {
            return .неОбычныйФайл
        }
        guard сведенияФайла.st_dev == сведенияИмени.st_dev,
              сведенияФайла.st_ino == сведенияИмени.st_ino else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "AGENTS.md изменился между fstatat и openat", код: EAGAIN
            )
        }
        guard сведенияФайла.st_size == off_t(ожидаемыеБайты.count) else {
            return .отличается
        }

        var прочитанныеБайты = Data(count: ожидаемыеБайты.count)
        try прочитанныеБайты.withUnsafeMutableBytes {
            (буфер: UnsafeMutableRawBufferPointer) throws -> Void in
            var смещение = 0
            while смещение < буфер.count {
                let число = Darwin.read(
                    файлFD,
                    буфер.baseAddress?.advanced(by: смещение),
                    буфер.count - смещение
                )
                if число > 0 {
                    смещение += число
                } else if число == 0 {
                    throw ОшибкаУстановщикаЛокальногоВхода.системная(
                        операция: "короткое чтение AGENTS.md", код: EIO
                    )
                } else if errno != EINTR {
                    throw ОшибкаУстановщикаЛокальногоВхода.системная(
                        операция: "ограниченное чтение AGENTS.md", код: errno
                    )
                }
            }
        }

        var сведенияПослеЧтения = stat()
        guard fstat(файлFD, &сведенияПослеЧтения) == 0 else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "fstat AGENTS.md после чтения", код: errno
            )
        }
        var сведенияИмениПослеЧтения = stat()
        guard fstatat(
            каталогFD,
            имяЦели,
            &сведенияИмениПослеЧтения,
            AT_SYMLINK_NOFOLLOW
        ) == 0 else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "fstatat AGENTS.md после чтения", код: errno
            )
        }
        guard (сведенияПослеЧтения.st_mode & S_IFMT) == S_IFREG,
              (сведенияИмениПослеЧтения.st_mode & S_IFMT) == S_IFREG,
              сведенияПослеЧтения.st_size == off_t(ожидаемыеБайты.count),
              сведенияПослеЧтения.st_dev == сведенияИмениПослеЧтения.st_dev,
              сведенияПослеЧтения.st_ino == сведенияИмениПослеЧтения.st_ino,
              сведенияПослеЧтения.st_mtimespec.tv_sec == сведенияФайла.st_mtimespec.tv_sec,
              сведенияПослеЧтения.st_mtimespec.tv_nsec == сведенияФайла.st_mtimespec.tv_nsec,
              сведенияПослеЧтения.st_ctimespec.tv_sec == сведенияФайла.st_ctimespec.tv_sec,
              сведенияПослеЧтения.st_ctimespec.tv_nsec == сведенияФайла.st_ctimespec.tv_nsec else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "AGENTS.md изменился во время ограниченного чтения", код: EAGAIN
            )
        }
        return прочитанныеБайты == ожидаемыеБайты ? .совпадает : .отличается
    }

    private static func подготовитьВременныйФайл(
        каталогFD: Int32,
        байты: Data
    ) throws -> String {
        let имя = префиксВременногоФайла + UUID().uuidString.lowercased() + ".tmp"
        let файлFD = openat(
            каталогFD,
            имя,
            O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC,
            mode_t(S_IRUSR | S_IWUSR)
        )
        guard файлFD >= 0 else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "исключительное создание временного файла", код: errno
            )
        }
        var файлОткрыт = true
        do {
            try записатьПолностью(байты, в: файлFD)
            guard fchmod(файлFD, mode_t(S_IRUSR | S_IWUSR | S_IRGRP | S_IROTH)) == 0 else {
                throw ОшибкаУстановщикаЛокальногоВхода.системная(
                    операция: "fchmod временного файла", код: errno
                )
            }
            try синхронизировать(файлFD, операция: "fsync временного файла")
            let итогЗакрытия = Darwin.close(файлFD)
            let кодЗакрытия = errno
            файлОткрыт = false
            guard итогЗакрытия == 0 else {
                throw ОшибкаУстановщикаЛокальногоВхода.неизвестныйОстатокВременногоФайла(
                    операция: "close временного файла", код: кодЗакрытия
                )
            }
            return имя
        } catch {
            var кодОшибкиЗакрытия: Int32?
            if файлОткрыт {
                let итогЗакрытия = Darwin.close(файлFD)
                if итогЗакрытия != 0 { кодОшибкиЗакрытия = errno }
                файлОткрыт = false
            }
            try очиститьВременныйФайл(
                каталогFD: каталогFD,
                имя: имя,
                контекст: "после отказа подготовки"
            )
            if let кодОшибкиЗакрытия {
                throw ОшибкаУстановщикаЛокальногоВхода.неизвестныйОстатокВременногоФайла(
                    операция: "close временного файла после отказа подготовки",
                    код: кодОшибкиЗакрытия
                )
            }
            throw error
        }
    }

    private static func очиститьВременныйФайл(
        каталогFD: Int32,
        имя: String,
        контекст: String
    ) throws {
        let итогУдаления = unlinkat(каталогFD, имя, 0)
        let кодУдаления = errno
        var синхронизацияНеПодтверждена = false
        var кодСинхронизации: Int32?
        do {
            try синхронизировать(каталогFD, операция: "fsync каталога при очистке")
        } catch let ошибка as ОшибкаУстановщикаЛокальногоВхода {
            синхронизацияНеПодтверждена = true
            кодСинхронизации = системныйКод(ошибка)
        } catch {
            синхронизацияНеПодтверждена = true
        }
        guard итогУдаления == 0 else {
            let уточнение = синхронизацияНеПодтверждена
                ? "; fsync каталога также не подтверждён"
                : ""
            throw ОшибкаУстановщикаЛокальногоВхода.неизвестныйОстатокВременногоФайла(
                операция: "unlinkat временного файла \(контекст)\(уточнение)",
                код: кодУдаления
            )
        }
        guard !синхронизацияНеПодтверждена else {
            throw ОшибкаУстановщикаЛокальногоВхода.неизвестныйОстатокВременногоФайла(
                операция: "fsync каталога после unlinkat \(контекст)",
                код: кодСинхронизации
            )
        }
    }

    private static func записатьПолностью(_ байты: Data, в файлFD: Int32) throws {
        try байты.withUnsafeBytes { (буфер: UnsafeRawBufferPointer) throws -> Void in
            var смещение = 0
            while смещение < буфер.count {
                let число = Darwin.write(
                    файлFD,
                    буфер.baseAddress?.advanced(by: смещение),
                    буфер.count - смещение
                )
                if число > 0 {
                    смещение += число
                } else if число == 0 {
                    throw ОшибкаУстановщикаЛокальногоВхода.системная(
                        операция: "нулевая запись временного файла", код: EIO
                    )
                } else if errno != EINTR {
                    throw ОшибкаУстановщикаЛокальногоВхода.системная(
                        операция: "запись временного файла", код: errno
                    )
                }
            }
        }
    }

    private static func синхронизировать(_ файлFD: Int32, операция: String) throws {
        while fsync(файлFD) != 0 {
            let код = errno
            if код == EINTR { continue }
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: операция, код: код
            )
        }
    }

    private static func системныйКод(_ ошибка: ОшибкаУстановщикаЛокальногоВхода) -> Int32? {
        if case .системная(_, let код) = ошибка { return код }
        return nil
    }

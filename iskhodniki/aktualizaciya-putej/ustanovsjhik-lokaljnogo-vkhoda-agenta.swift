    private static func разобрать(_ аргументы: [String]) throws -> Параметры {
        var корень: String?
        var обёртка: String?
        var индекс = 0
        while индекс < аргументы.count {
            guard индекс + 1 < аргументы.count else {
                throw ОшибкаУстановщикаЛокальногоВхода.системная(
                    операция: "ожидалось значение аргумента \(аргументы[индекс])", код: EINVAL
                )
            }
            let значение = аргументы[индекс + 1]
            switch аргументы[индекс] {
            case "--корень" where корень == nil:
                корень = значение
            case "--обёртка" where обёртка == nil:
                обёртка = значение
            default:
                throw ОшибкаУстановщикаЛокальногоВхода.системная(
                    операция: "неизвестный или повторный аргумент \(аргументы[индекс])", код: EINVAL
                )
            }
            индекс += 2
        }
        guard let корень, let обёртка else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "требуются --корень и --обёртка", код: EINVAL
            )
        }
        return Параметры(корень: корень, обёртка: обёртка)
    }

    private static func прочитатьОбёртку(_ путь: String) throws -> Data {
        let файлFD = open(путь, O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC)
        guard файлFD >= 0 else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "open обёртки без перехода по ссылке", код: errno
            )
        }
        defer { _ = Darwin.close(файлFD) }
        var сведения = stat()
        guard fstat(файлFD, &сведения) == 0 else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "fstat обёртки", код: errno
            )
        }
        let предел = 1024 * 1024
        guard (сведения.st_mode & S_IFMT) == S_IFREG,
              сведения.st_size >= 0,
              сведения.st_size <= off_t(предел) else {
            throw ОшибкаУстановщикаЛокальногоВхода.системная(
                операция: "обёртка не является ограниченным обычным файлом", код: EFBIG
            )
        }
        var байты = Data(count: Int(сведения.st_size))
        try байты.withUnsafeMutableBytes {
            (буфер: UnsafeMutableRawBufferPointer) throws -> Void in
            var смещение = 0
            while смещение < буфер.count {
                let число = Darwin.read(
                    файлFD,
                    буфер.baseAddress?.advanced(by: смещение),
                    буфер.count - смещение
                )
                if число > 0 {
                    смещение += число
                } else if число == 0 {
                    throw ОшибкаУстановщикаЛокальногоВхода.системная(
                        операция: "короткое чтение обёртки", код: EIO
                    )
                } else if errno != EINTR {
                    throw ОшибкаУстановщикаЛокальногоВхода.системная(
                        операция: "чтение обёртки", код: errno
                    )
                }
            }
        }
        return байты
    }

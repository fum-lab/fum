import Foundation
import CryptoKit

enum РольАртефактаКандидатов: String, Sendable { case основа, результат, управление, журнал, неизвестныйОстаток }
struct АртефактКандидатов: Equatable, Sendable {
    let путь: String
    let хэш: String
    let размер: Int
    let роль: РольАртефактаКандидатов
}
struct УчтённаяКоллекцияКандидатов: Sendable {
    let идентификатор: String
    let хэшПрофиля: String
    let артефакты: [АртефактКандидатов]
    let занято: Int
    let предел: Int
    let хэшСостава: String
    let содержитНеизвестныеОстатки: Bool
    let физическиеФайлыПроверены = false
    let продолжениеРазрешено = false
    let применениеРазрешено = false
    fileprivate init(идентификатор: String, хэшПрофиля: String, артефакты: [АртефактКандидатов], занято: Int, предел: Int, хэшСостава: String) {
        self.идентификатор = идентификатор; self.хэшПрофиля = хэшПрофиля; self.артефакты = артефакты
        self.занято = занято; self.предел = предел; self.хэшСостава = хэшСостава
        self.содержитНеизвестныеОстатки = артефакты.contains { $0.роль == .неизвестныйОстаток }
    }
    func свободноДляДанных(резервУправления: Int) throws -> Int {
        guard (0...4_194_304).contains(резервУправления), резервУправления <= предел - занято else {
            throw ОтказСсылокПакета.условие("не-помещается-резерв-коллекции")
        }
        return предел - занято - резервУправления
    }
}
enum УчётАртефактовКандидатов {
    static func создать(идентификатор: String, хэшПрофиля: String, артефакты: [АртефактКандидатов], предел: Int = 134_217_728) throws -> УчтённаяКоллекцияКандидатов {
        guard идентификатор.utf8.count == 36, UUID(uuidString: идентификатор)?.uuidString.lowercased() == идентификатор,
              верныйХэш(хэшПрофиля), (0...134_217_728).contains(предел), артефакты.count <= 65_536 else {
            throw ОтказСсылокПакета.условие("неверные-опоры-учёта-артефактов")
        }
        var записи: [Data: АртефактКандидатов] = [:], занято = 0
        for артефакт in артефакты {
            try ИменаПутей.проверитьПуть(артефакт.путь)
            guard артефакт.путь.utf8.allSatisfy({ (97...122).contains($0) || (48...57).contains($0) || [45, 46, 47].contains($0) }),
                  ИменаПутей.компоненты(артефакт.путь).count <= 64, верныйХэш(артефакт.хэш),
                  (0...33_554_432).contains(артефакт.размер) else { throw ОтказСсылокПакета.условие("неверная-запись-артефакта") }
            let ключ = Data(артефакт.путь.utf8)
            if let прежняя = записи[ключ] {
                guard прежняя == артефакт else { throw ОтказСсылокПакета.условие("дрейф-учтённого-артефакта") }
                continue
            }
            guard записи.count < 32_768, артефакт.размер <= предел - занято else { throw ОтказСсылокПакета.условие("предел-коллекции-артефактов") }
            записи[ключ] = артефакт; занято += артефакт.размер
        }
        let упорядоченныеКлючи = записи.keys.sorted { $0.lexicographicallyPrecedes($1) }
        var работаПрефиксов = 0
        for ключ in упорядоченныеКлючи {
            var предок = ключ
            while let граница = предок.lastIndex(of: 47) {
                let длина = предок.distance(from: предок.startIndex, to: граница)
                guard длина <= 67_108_864 - работаПрефиксов else { throw ОтказСсылокПакета.условие("предел-проверки-префиксов-артефактов") }
                работаПрефиксов += длина
                предок = Data(предок[..<граница])
                guard записи[предок] == nil else { throw ОтказСсылокПакета.условие("файл-стал-предком-артефакта") }
            }
        }
        let упорядоченные = упорядоченныеКлючи.map { записи[$0]! }
        var хэш = SHA256()
        func число(_ значение: Int) {
            var сетевое = UInt64(значение).bigEndian
            withUnsafeBytes(of: &сетевое) { хэш.update(data: Data($0)) }
        }
        func поле(_ значение: String) { число(значение.utf8.count); хэш.update(data: Data(значение.utf8)) }
        поле("fum.учёт-артефактов-кандидатов.1"); поле(идентификатор); поле(хэшПрофиля)
        число(предел); число(упорядоченные.count)
        for запись in упорядоченные { поле(запись.путь); поле(запись.хэш); число(запись.размер); поле(запись.роль.rawValue) }
        return .init(идентификатор: идентификатор, хэшПрофиля: хэшПрофиля, артефакты: упорядоченные, занято: занято, предел: предел,
            хэшСостава: хэш.finalize().map { String(format: "%02x", $0) }.joined())
    }
    static func дополнить(_ прежняя: УчтённаяКоллекцияКандидатов, идентификатор: String, хэшПрофиля: String,
        артефакты: [АртефактКандидатов]) throws -> УчтённаяКоллекцияКандидатов {
        guard идентификатор.utf8.count == 36, верныйХэш(хэшПрофиля), идентификатор == прежняя.идентификатор,
              хэшПрофиля == прежняя.хэшПрофиля, артефакты.count <= 32_768 else {
            throw ОтказСсылокПакета.условие("чужая-коллекция-или-профиль")
        }
        return try создать(идентификатор: идентификатор, хэшПрофиля: хэшПрофиля, артефакты: прежняя.артефакты + артефакты, предел: прежняя.предел)
    }
    private static func верныйХэш(_ значение: String) -> Bool {
        значение.utf8.count == 64 && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
}

struct КонтекстКандидатовАдресов: Sendable {
    let исходные: [Data: ВидУзлаМиграции]
    let будущие: [Data: ВидУзлаМиграции]
    let соответствия: [Data: String]
    let удаляемые: Set<Data>
    let исходныеАлиасы: Set<Data>
    let будущиеАлиасы: Set<Data>
    let хэшОпоры: String
    let хэшСостава: String
    let внешнийДопускПроверен = false
    private init(исходные: [Data: ВидУзлаМиграции], будущие: [Data: ВидУзлаМиграции], соответствия: [Data: String], удаляемые: Set<Data>,
        исходныеАлиасы: Set<Data>, будущиеАлиасы: Set<Data>, хэшОпоры: String, хэшСостава: String) {
        self.исходные = исходные; self.будущие = будущие; self.соответствия = соответствия; self.удаляемые = удаляемые
        self.исходныеАлиасы = исходныеАлиасы; self.будущиеАлиасы = будущиеАлиасы; self.хэшОпоры = хэшОпоры; self.хэшСостава = хэшСостава
    }
    static func подготовить(исходные: [ЦельПространстваАдресов], будущие: [ЦельПространстваАдресов],
        соответствия: [СтрокаОбщегоОтображения], удаляемые: [String] = [], хэшОпоры: String) throws -> Self {
        guard исходные.count <= 100_000, будущие.count <= 100_000, соответствия.count <= 100_000, удаляемые.count <= 100_000,
              хэшОпоры.utf8.count == 64, хэшОпоры.utf8.allSatisfy({ (48...57).contains($0) || (97...102).contains($0) }) else { throw ОтказСсылокПакета.условие("неверные-границы-контекста-адресов") }
        var суммаПутей = 0, суммаНормализованных = 0, шаги = 268_435_456
        func путь(_ значение: String, корень: Bool = false) throws -> Data {
            guard значение.utf8.count <= 1024, значение.utf8.count <= 67_108_864 - суммаПутей else { throw ОтказСсылокПакета.условие("предел-путей-контекста-адресов") }
            if !(корень && значение.isEmpty) { try ИменаПутей.проверитьПуть(значение) }
            суммаПутей += значение.utf8.count
            return Data(значение.utf8)
        }
        func пространство(_ записи: [ЦельПространстваАдресов]) throws -> ([Data: ВидУзлаМиграции], Set<Data>) {
            var итог: [Data: ВидУзлаМиграции] = [:], алиасы: Set<Data> = [], нормализованные: [Data: Data] = [:]
            for запись in записи {
                let ключ = try путь(запись.путь, корень: true)
                guard (!ключ.isEmpty || запись.вид == .каталог), итог.updateValue(запись.вид, forKey: ключ) == nil else { throw ОтказСсылокПакета.условие("дубли-или-неверный-корень-пространства-адресов") }
                let нормализованный = ИменаПутей.ключКоллизии(запись.путь)
                guard нормализованный.count <= 67_108_864 - суммаНормализованных else { throw ОтказСсылокПакета.условие("предел-алиасов-пространства-адресов") }
                суммаНормализованных += нормализованный.count
                if let прежний = нормализованные[нормализованный], прежний != ключ { алиасы.insert(прежний); алиасы.insert(ключ) }
                else { нормализованные[нормализованный] = ключ }
            }
            if итог[Data()] == nil { итог[Data()] = .каталог }
            for ключ in итог.keys where !ключ.isEmpty {
                let родитель = ключ.lastIndex(of: 47).map { Data(ключ[..<$0]) } ?? Data()
                guard итог[родитель] == .каталог else { throw ОтказСсылокПакета.условие("нет-директориального-предка-пространства-адресов") }
            }
            return (итог, алиасы)
        }
        let (старые, старыеАлиасы) = try пространство(исходные), (новые, новыеАлиасы) = try пространство(будущие)
        var карта: [Data: String] = [:], удаление: Set<Data> = []
        for имя in удаляемые {
            let ключ = try путь(имя)
            guard старые[ключ] != nil, удаление.insert(ключ).inserted else { throw ОтказСсылокПакета.условие("неверное-удаление-пространства-адресов") }
        }
        for пара in соответствия {
            let исходный = try путь(пара.исходный), целевой = try путь(пара.целевой)
            guard let вид = старые[исходный], новые[целевой] == вид,
                  карта.updateValue(пара.целевой, forKey: исходный) == nil else { throw ОтказСсылокПакета.условие("неверное-соответствие-пространства-адресов") }
            var предок = исходный
            while !предок.isEmpty {
                guard предок.count <= шаги else { throw ОтказСсылокПакета.условие("предел-предков-контекста-адресов") }
                шаги -= предок.count
                guard !удаление.contains(предок) else { throw ОтказСсылокПакета.условие("удаление-конфликтует-с-соответствием") }
                предок = предок.lastIndex(of: 47).map { Data(предок[..<$0]) } ?? Data()
            }
        }
        // Отпечаток связывает только объявленный состав и непрозрачную опору.
        // Он не доказывает источник графа, байты ФС либо допуск ROOT.
        var хэш = SHA256()
        func число(_ значение: Int) {
            var сетевое = UInt64(значение).bigEndian
            withUnsafeBytes(of: &сетевое) { хэш.update(data: Data($0)) }
        }
        func поле(_ байты: Data) { число(байты.count); хэш.update(data: байты) }
        поле(Data("fum.контекст-кандидатов-адресов.1".utf8)); поле(Data(хэшОпоры.utf8))
        for набор in [старые, новые] {
            число(набор.count)
            for ключ in набор.keys.sorted(by: { $0.lexicographicallyPrecedes($1) }) {
                поле(ключ); поле(Data(набор[ключ]!.rawValue.utf8))
            }
        }
        число(карта.count)
        for ключ in карта.keys.sorted(by: { $0.lexicographicallyPrecedes($1) }) { поле(ключ); поле(Data(карта[ключ]!.utf8)) }
        число(удаление.count)
        for ключ in удаление.sorted(by: { $0.lexicographicallyPrecedes($1) }) { поле(ключ) }
        let отпечаток = хэш.finalize().map { String(format: "%02x", $0) }.joined()
        return .init(исходные: старые, будущие: новые, соответствия: карта, удаляемые: удаление,
            исходныеАлиасы: старыеАлиасы, будущиеАлиасы: новыеАлиасы, хэшОпоры: хэшОпоры, хэшСостава: отпечаток)
    }
}

import Foundation
import CryptoKit

struct ПроектПространстваАдресов: Sendable {
    let контекст: КонтекстКандидатовАдресов?
    let отображения: [СтрокаОбщегоОтображения]
    let группы: [ГруппаОбщейМиграции]
    let удаляемыеЛистья: [Data]
    let препятствия: [ПрепятствиеОбщейМиграции]
    let похожеНаПовтор: Bool
    let деревоПереставленныхИсходныхОбъектов: String?
    let хэшОпоры: String
    let содержимоеОбъектовПроверено = false
    let файловаяСистемаПроверена = false
    let имяКорняПроверено = false
    let повторДоказан = false
    let собственныеВходыВключены = false
    let применениеРазрешено = false
}

enum ПереходПространстваАдресов {
    static func построить(_ пространство: ПроверенноеПространствоИмёнGit,
        ожидаемоеДерево: String, ожидаемыйХэшИндекса: String, ожидаемыйХэшПеречня: String,
        корень: КорневоеОтображениеМиграции, исключитьПроекцию: Bool,
        пределУзлов: Int = 100_000, пределБайтовПутей: Int = 67_108_864) throws -> ПроектПространстваАдресов {
        guard (1...100_000).contains(пределУзлов), (0...67_108_864).contains(пределБайтовПутей),
              пространство.листья.count < пределУзлов,
              пространство.каталоги.count <= пределУзлов - 1 - пространство.листья.count,
              ожидаемоеДерево == пространство.дерево, ожидаемыйХэшИндекса == пространство.хэшИндекса,
              ожидаемыйХэшПеречня == пространство.хэшСырогоПеречня,
              !корень.источникИмени.isEmpty, корень.источникИмени.utf8.count <= 65_536,
              корень.ревизия == "837e2ce107b97ee7b9d3344c9fe99142281fe393" else {
            throw ОтказСсылокПакета.условие("неверные-опоры-или-пределы-моста")
        }
        for имя in [корень.исходный, корень.целевой] {
            try ИменаПутей.проверитьПуть(имя)
            guard !имя.utf8.contains(47) else { throw ОтказСсылокПакета.условие("мосту-нужен-верхний-корень") }
        }
        var хэш = SHA256()
        for поле in ["fum.мост-пространства-адресов.1", пространство.дерево, пространство.хэшИндекса, пространство.хэшСырогоПеречня,
            корень.исходный, корень.целевой, корень.источникИмени, корень.ревизия, исключитьПроекцию ? "1" : "0"] {
            var длина = UInt64(поле.utf8.count).bigEndian
            withUnsafeBytes(of: &длина) { хэш.update(data: Data($0)) }
            хэш.update(data: Data(поле.utf8))
        }
        let хэшОпоры = хэш.finalize().map { String(format: "%02x", $0) }.joined()
        var суммаПутей = 0
        func учесть(_ путь: Data) throws {
            guard путь.count <= 1024, путь.count <= пределБайтовПутей - суммаПутей else {
                throw ОтказСсылокПакета.условие("предел-путей-моста")
            }
            суммаПутей += путь.count
        }
        let исходный = Data(корень.исходный.utf8), целевой = Data(корень.целевой.utf8), проекция = Data("Proyekcii".utf8)
        func внутри(_ путь: Data, _ корень: Data) -> Bool { путь == корень || путь.starts(with: корень + Data([47])) }
        var старые: [Data: ВидУзлаМиграции] = [:]
        for путь in пространство.каталоги { try учесть(путь); старые[путь] = .каталог }
        var листья: [Data: ЛистДереваGit] = [:]
        for лист in пространство.листья {
            try учесть(лист.путь); листья[лист.путь] = лист
            старые[лист.путь] = switch лист.вид {
            case .файл: .файл
            case .символическаяСсылка: .ссылка
            case .внешняяЗависимость: .внешняяГраница
            }
        }
        var отображения: [СтрокаОбщегоОтображения] = [], группы: [ГруппаОбщейМиграции] = []
        var удаляемыеЛистья: [Data] = [], похожеНаПовтор = false
        func ключОшибки(_ запись: ПрепятствиеОбщейМиграции) -> Data {
            var ключ = Data()
            for текст in [запись.код] + запись.пути {
                var длина = UInt64(текст.utf8.count).bigEndian
                withUnsafeBytes(of: &длина) { ключ.append(contentsOf: $0) }
                ключ.append(contentsOf: текст.utf8)
            }
            return ключ
        }
        var реестрПрепятствий: [Data: ПрепятствиеОбщейМиграции] = [:]
        for запись in пространство.коллизии { реестрПрепятствий[ключОшибки(запись)] = запись }
        func препятствие(_ код: String, _ пути: [Data]) {
            let запись = ПрепятствиеОбщейМиграции(код: код, пути: пути.sorted { $0.lexicographicallyPrecedes($1) }.map { String(decoding: $0, as: UTF8.self) })
            реестрПрепятствий[ключОшибки(запись)] = запись
        }
        func результат(_ контекст: КонтекстКандидатовАдресов? = nil, _ дерево: String? = nil) -> ПроектПространстваАдресов {
            .init(контекст: контекст, отображения: отображения, группы: группы, удаляемыеЛистья: удаляемыеЛистья,
                препятствия: реестрПрепятствий.keys.sorted { $0.lexicographicallyPrecedes($1) }.map { реестрПрепятствий[$0]! },
                похожеНаПовтор: похожеНаПовтор, деревоПереставленныхИсходныхОбъектов: дерево, хэшОпоры: хэшОпоры)
        }
        if исключитьПроекцию && (исходный == проекция || целевой == проекция) {
            препятствие("проекция-пересекается-с-переходом", [исходный, целевой]); return результат()
        }
        let верхние = старые.keys.filter { !$0.contains(47) }
        for имя in [исходный, целевой] {
            let ключ = ИменаПутей.ключКоллизии(String(decoding: имя, as: UTF8.self))
            for сосед in верхние where сосед != имя {
                if ИменаПутей.ключКоллизии(String(decoding: сосед, as: UTF8.self)) == ключ {
                    препятствие("алиас-корня-перехода", [имя, сосед])
                }
            }
        }
        if let вид = старые[исходный], вид != .каталог { препятствие("исходный-корень-не-каталог", [исходный]) }
        if let вид = старые[целевой], вид != .каталог { препятствие("целевой-корень-не-каталог", [целевой]) }
        if исключитьПроекцию, let вид = старые[проекция], вид != .каталог { препятствие("корень-проекции-не-каталог", [проекция]) }
        if старые[исходный] == nil {
            if старые[целевой] == .каталог { похожеНаПовтор = true }
            else { препятствие("нет-источника-и-назначения-моста", [исходный, целевой]) }
        }
        var назначения: [Data: [(исходный: Data, вид: ВидУзлаМиграции)]] = [:]
        for путь in старые.keys.sorted(by: { $0.lexicographicallyPrecedes($1) }) {
            if исключитьПроекцию && внутри(путь, проекция) {
                if листья[путь] != nil { удаляемыеЛистья.append(путь) }
                continue
            }
            let цель: Data
            if внутри(путь, исходный) {
                let хвост = путь.dropFirst(исходный.count)
                guard хвост.count <= 1024 - целевой.count else { throw ОтказСсылокПакета.условие("предел-перенесённого-пути-моста") }
                цель = целевой + хвост
            } else { цель = путь }
            // Обе стороны каждой строки входят в тот же общий бюджет context.
            try учесть(путь); try учесть(цель)
            отображения.append(.init(исходный: String(decoding: путь, as: UTF8.self), целевой: String(decoding: цель, as: UTF8.self)))
            назначения[цель, default: []].append((путь, старые[путь]!))
        }
        guard назначения.count < пределУзлов else { throw ОтказСсылокПакета.условие("предел-будущих-узлов-моста") }
        var будущие: [ЦельПространстваАдресов] = [], будущиеЛистья: [ЛистДереваGit] = []
        var алиасы: [Data: Set<Data>] = [:], суммаКлючей = 0
        for цель in назначения.keys.sorted(by: { $0.lexicographicallyPrecedes($1) }) {
            try учесть(цель)
            let участники = назначения[цель]!, пути = участники.map(\.исходный)
            let всеКаталоги = участники.allSatisfy { $0.вид == .каталог }
            let вид: ВидГруппыМиграции
            if участники.count > 1 {
                if всеКаталоги { вид = .объединениеКаталогов }
                else {
                    вид = .препятствие
                    препятствие(участники.allSatisfy({ $0.вид != .каталог }) ? "не-проверено-совпадение-листьев" : "коллизия-типов-назначения", пути)
                }
            } else { вид = пути[0] == цель ? .неподвижная : .перенос }
            группы.append(.init(целевой: String(decoding: цель, as: UTF8.self), исходные: пути.map { String(decoding: $0, as: UTF8.self) }, вид: вид))
            if вид != .препятствие {
                будущие.append(.init(путь: String(decoding: цель, as: UTF8.self), вид: участники[0].вид))
                if var лист = листья[пути[0]] { лист.путь = цель; будущиеЛистья.append(лист) }
            }
            let ключ = ИменаПутей.ключКоллизии(String(decoding: цель, as: UTF8.self))
            guard ключ.count <= 67_108_864 - суммаКлючей else { throw ОтказСсылокПакета.условие("предел-ключей-моста") }
            суммаКлючей += ключ.count
            алиасы[ключ, default: []].insert(цель)
        }
        for группа in алиасы.values where группа.count > 1 { препятствие("алиасы-будущего-пространства-моста", Array(группа)) }
        let удаляемые = исключитьПроекцию && старые[проекция] != nil ? ["Proyekcii"] : []
        if !удаляемые.isEmpty { try учесть(проекция) }
        // Ни одинаковый OID, ни mode не доказывают будущие байты и цели ссылок.
        guard реестрПрепятствий.isEmpty else { return результат() }
        let контекст = try КонтекстКандидатовАдресов.подготовить(
            исходные: старые.map { .init(путь: String(decoding: $0.key, as: UTF8.self), вид: $0.value) },
            будущие: будущие, соответствия: отображения, удаляемые: удаляемые, хэшОпоры: хэшОпоры)
        let дерево = try ПространствоИмёнGit.вычислитьДерево(будущиеЛистья)
        return результат(контекст, дерево)
    }
}

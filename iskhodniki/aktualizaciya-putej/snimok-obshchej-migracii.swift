import Foundation
import CryptoKit

struct ФайлИнвентаряМиграции: Codable, Equatable, Sendable {
    var путь: String
    var физическийПуть: String
    var режим: String
    var объект: String
    var sha256: String
    var размер: Int
}

struct ОбластьИнвентаряМиграции: Codable, Equatable, Sendable {
    var корень: String
    var дерево: String
    var переченьПутейSHA256: String
    var файлы: [ФайлИнвентаряМиграции]
}

struct ИнвентарьОбщейМиграции: Codable, Equatable, Sendable {
    var схема = "fum.инвентарь-общей-миграции-путей.1"
    var физическийКорень: String
    var основа: ОсноваОбщейМиграции
    var пространствоSHA256: String
    var корни: [КорневоеОтображениеМиграции]
    var области: [ОбластьИнвентаряМиграции]
    var удаляемаяПроекция: String?
    var отсутствующиеНазначения: [String]
    var отсутствующиеОбласти: [String]
    var физическиеПрепятствия: [ПрепятствиеОбщейМиграции]
    var полнотаФизическогоСоставаПроверена: Bool
    var применениеРазрешено = false
}

struct СнятаяОбщаяМиграция {
    var инвентарь: ИнвентарьОбщейМиграции
    var узлы: [УзелОбщейМиграции]
}

enum ЧитательОбщейМиграции {
    // Этот вход только читает верхние области. Проекция раскрывается только
    // для точного manifest удаления; её содержимое не становится каноническим.
    static func снять(корень: URL, ожидаемаяОснова: ОсноваОбщейМиграции,
        переносимыеКорни: [String], удаляемаяПроекция: String? = nil,
        послеЧтенияДляПроверки: (() throws -> Void)? = nil) async throws -> СнятаяОбщаяМиграция {
        guard удаляемаяПроекция == nil || удаляемаяПроекция == "Proyekcii" else { throw ОтказОбщейМиграции.условие("не-точная-производная-область") }
        var отображения: [КорневоеОтображениеМиграции] = []
        for исходный in переносимыеКорни {
            try ИменаПутей.проверитьПуть(исходный)
            guard !исходный.utf8.contains(47), исходный != "Proyekcii" else { throw ОтказОбщейМиграции.условие("нужен-канонический-верхний-корень") }
            let имя = try await ПубличныйФасадИмён.канонизировать(исходный)
            guard let происхождение = String(data: try байтыПлана(имя.происхождение), encoding: .utf8) else { throw ОтказОбщейМиграции.условие("не-UTF8-происхождение-имени") }
            отображения.append(.init(исходный: исходный, целевой: имя.значение, источникИмени: происхождение, ревизия: имя.происхождение.ревизияЗависимости))
        }
        let области = Set(переносимыеКорни + отображения.map(\.целевой) + (удаляемаяПроекция.map { [$0] } ?? []))
        guard !области.isEmpty else { throw ОтказОбщейМиграции.условие("пустой-инвентарь") }
        var политика = try ПолитикаГраницПутей.принятая()
        if let удаляемаяПроекция { политика.исключённые_префиксы.removeAll { $0 == удаляемаяПроекция } }
        let чтение = try ЧитательПутей.снять(корень: корень, области: области.sorted(by: порядокПутей), политика: политика,
            пределСохраняемогоФайла: 33_554_432, пределВсехБайтов: 268_435_456, допустимоОтсутствуют: области, послеЧтенияДляПроверки: послеЧтенияДляПроверки)
        let снимок = чтение.снимок
        let основа = ОсноваОбщейМиграции(корневаяЗадача: ожидаемаяОснова.корневаяЗадача, владелец: ожидаемаяОснова.владелец,
            ветка: снимок.ветка, коммит: снимок.коммит, дерево: снимок.дерево, индексSHA256: снимок.индекс_sha256)
        guard try байтыПлана(основа) == байтыПлана(ожидаемаяОснова), !снимок.индекс_изменён else { throw ОтказОбщейМиграции.условие("дрейф-основы-инвентаря") }
        var отсутствующие: [String] = []
        let соседи = чтение.соседи[Data()] ?? []
        let отсутствующиеОбласти = области.filter { область in
            !соседи.contains { ИменаПутей.ключКоллизии(String(decoding: $0, as: UTF8.self)) == ИменаПутей.ключКоллизии(область) }
        }
        for отображение in отображения {
            guard !отсутствующиеОбласти.contains(отображение.исходный) || !отсутствующиеОбласти.contains(отображение.целевой) else {
                throw ОтказОбщейМиграции.условие("нет-источника-и-назначения")
            }
            let алиасы = соседи.filter { ИменаПутей.ключКоллизии(String(decoding: $0, as: UTF8.self)) == ИменаПутей.ключКоллизии(отображение.целевой) }
            if алиасы.isEmpty { отсутствующие.append(отображение.целевой) }
            else {
                guard алиасы.count == 1, алиасы[0] == Data(отображение.целевой.utf8) else { throw ОтказОбщейМиграции.условие("алиас-назначения-инвентаря") }
                // Имеющееся назначение должно войти в отдельный полный census.
                guard области.contains(отображение.целевой) else { throw ОтказОбщейМиграции.условие("назначение-требует-UNION-инвентаря") }
            }
        }
        var файлы: [ФайлИнвентаряМиграции] = [], узлы: [УзелОбщейМиграции] = []
        var физическиеПрепятствия: [ПрепятствиеОбщейМиграции] = []
        var каталогиGit: [Data: Set<Data>] = [:]
        for запись in снимок.записи {
            guard let путь = запись.путь_индекса else { continue }
            var родитель = (путь as NSString).deletingLastPathComponent
            while !родитель.isEmpty {
                каталогиGit[Data(родитель.precomposedStringWithCanonicalMapping.utf8), default: []].insert(Data(родитель.utf8))
                родитель = (родитель as NSString).deletingLastPathComponent
            }
        }
        func логическийКаталог(_ физический: String) throws -> String {
            let варианты = каталогиGit[Data(физический.precomposedStringWithCanonicalMapping.utf8)] ?? []
            guard варианты.count == 1, let путь = варианты.first else { throw ОтказОбщейМиграции.условие("нет-однозначного-Git-префикса: " + физический) }
            return String(decoding: путь, as: UTF8.self)
        }
        for запись in снимок.записи {
            guard запись.тип == "файл" || запись.тип == "каталог" else {
                физическиеПрепятствия.append(.init(код: "не-раскрытая-физическая-граница", пути: [запись.путь]))
                continue
            }
            let путь = try запись.тип == "каталог" ? логическийКаталог(запись.путь) : (запись.путь_индекса ?? запись.путь)
            if запись.тип == "каталог" {
                if удаляемаяПроекция.map({ ИменаПутей.вложен(путь, в: $0) }) != true { узлы.append(.init(путь: путь, вид: .каталог, режим: "040000")) }
                continue
            }
            guard запись.путь_индекса != nil, let объект = запись.объект,
                  let байты = чтение.тексты[Data(запись.путь.utf8)], запись.режим == запись.режим_индекса,
                  хэшПутей(байты) == запись.sha256 else { throw ОтказОбщейМиграции.условие("неотслеживаемый-или-изменённый-файл-инвентаря") }
            let заголовок = Data("blob \(байты.count)\0".utf8)
            let вычисленныйОбъект = Insecure.SHA1.hash(data: заголовок + байты).map { String(format: "%02x", $0) }.joined()
            guard вычисленныйОбъект == объект else { throw ОтказОбщейМиграции.условие("байты-не-совпали-с-Git-объектом") }
            файлы.append(.init(путь: путь, физическийПуть: запись.путь, режим: запись.режим, объект: объект, sha256: хэшПутей(байты), размер: байты.count))
            if удаляемаяПроекция.map({ ИменаПутей.вложен(путь, в: $0) }) != true {
                узлы.append(.init(путь: путь, вид: .файл, режим: запись.режим, объект: объект, байты: байты))
            }
        }
        var непустыеКаталоги: Set<Data> = []
        for файл in файлы {
            var родитель = (файл.путь as NSString).deletingLastPathComponent
            while !родитель.isEmpty { непустыеКаталоги.insert(Data(родитель.utf8)); родитель = (родитель as NSString).deletingLastPathComponent }
        }
        for запись in снимок.записи where запись.тип == "каталог" {
            let путь = try логическийКаталог(запись.путь)
            guard непустыеКаталоги.contains(Data(путь.utf8)) else { throw ОтказОбщейМиграции.условие("лишний-пустой-каталог") }
        }
        var итоги: [ОбластьИнвентаряМиграции] = []
        for область in области.sorted(by: порядокПутей) {
            if отсутствующиеОбласти.contains(область) { continue }
            let выбранные = файлы.filter { ИменаПутей.вложен($0.путь, в: область) }.sorted { порядокПутей($0.путь, $1.путь) }
            let дерево = try ЧитательПутей.гит(корень, ["rev-parse", снимок.коммит + ":" + область]).0
            guard let строка = String(data: дерево, encoding: .utf8) else { throw ОтказОбщейМиграции.условие("не-UTF8-дерево-области") }
            let перечень = выбранные.reduce(into: Data()) { $0.append(Data($1.путь.utf8)); $0.append(0) }
            итоги.append(.init(корень: область, дерево: строка.trimmingCharacters(in: .newlines), переченьПутейSHA256: хэшПутей(перечень), файлы: выбранные))
        }
        return .init(инвентарь: .init(физическийКорень: корень.path, основа: основа, пространствоSHA256: снимок.пространство_sha256,
            корни: отображения.sorted { порядокПутей($0.исходный, $1.исходный) }, области: итоги, удаляемаяПроекция: удаляемаяПроекция, отсутствующиеНазначения: отсутствующие.sorted(by: порядокПутей), отсутствующиеОбласти: отсутствующиеОбласти.sorted(by: порядокПутей),
            физическиеПрепятствия: физическиеПрепятствия, полнотаФизическогоСоставаПроверена: физическиеПрепятствия.isEmpty), узлы: узлы)
    }
}

import Foundation
import Darwin

struct ВходПланированияДокументации: Codable, Sendable {
    var корневаяЗадача: String
    var владелец: String
    var ожидаемыйКоммит: String
    var ожидаемаяВетка: String
    var времяСвежести: String
    var времяЖурнала: String
    var объединитьREADME: Bool
    var входящие: [ВходящийДокументПакетаДокументации]
}

enum ПакетноеОбъединениеДокументации {
    static func построить(корень: URL, вход: ВходПланированияДокументации) throws -> ПакетИсполненияДокументации {
        try ПримитивыДокументации.абсолютныйКаталог(корень)
        let коммит = try ПримитивыДокументации.текстГит(корень, ["rev-parse", "HEAD"])
        let ветка = try ПримитивыДокументации.текстГит(корень, ["symbolic-ref", "HEAD"])
        try ПримитивыДокументации.требовать(коммит == вход.ожидаемыйКоммит && ветка == вход.ожидаемаяВетка
            && ПримитивыДокументации.текстГит(корень, ["rev-parse", "--show-toplevel"]) == корень.path, "другая-основа-производителя")
        let каталогGit = URL(fileURLWithPath: try ПримитивыДокументации.текстГит(корень, ["rev-parse", "--path-format=absolute", "--git-dir"]))
        try ПримитивыДокументации.абсолютныйКаталог(каталогGit)
        try ПримитивыДокументации.требовать(try !ПримитивыДокументации.есть(каталогGit.appendingPathComponent("index.lock")), "занят-index")
        let физическийИндекс = try ПримитивыДокументации.прочитать(каталогGit.appendingPathComponent("index"), предел: 67_108_864)
        let логическийИндекс = try ПримитивыДокументации.гит(корень, ["ls-files", "--stage", "-z"])
        let индекс = try ПримитивыДокументации.индекс(логическийИндекс)
        let состав = try ПримитивыДокументации.снимокСостава(корень)
        var узлы: [УзелОбщейМиграции] = []
        for путь in состав.0.keys.sorted(by: порядокПутей) {
            let сведения = состав.0[путь]!
            let индексные = индекс.values.filter { Data($0.путь.precomposedStringWithCanonicalMapping.utf8) == Data(путь.precomposedStringWithCanonicalMapping.utf8) }
            try ПримитивыДокументации.требовать(индексные.count <= 1, "NFC-алиас-индекса-производителя")
            let запись = индексные.first
            let логическийПуть = запись?.путь ?? путь
            if сведения.вид == "каталог" { узлы.append(.init(путь: логическийПуть, вид: .каталог, режим: "040000")); continue }
            guard let байты = состав.1[путь] else { throw ОтказАдаптераДокументации.условие("потерян-buffer-снимка") }
            if логическийПуть.hasPrefix("Документация/") {
                try ПримитивыДокументации.требовать(запись?.объект == ПримитивыДокументации.объектGit(байты)
                    && запись?.режим == сведения.режим, "грязный-или-untracked-источник-перед-MOVE")
            }
            узлы.append(.init(путь: логическийПуть, вид: .файл, режим: сведения.режим ?? "100644", объект: запись?.объект ?? "", байты: байты))
        }
        let пространство = try ПримитивыДокументации.пространство(корень, индекс: логическийИндекс, узлыDocs: узлы.map(\.путь))
        let отображения = узлы.sorted { порядокПутей($0.путь, $1.путь) }.map {
            СтрокаОбщегоОтображения(исходный: $0.путь, целевой: ПрофильОбъединенияДокументации.назначение($0.путь))
        }
        let поПути = Dictionary(uniqueKeysWithValues: узлы.map { (Data($0.путь.utf8), $0) })
        var каноны: [КаноническаяКопияДокументации] = [], доказательства: [ДоказательствоКопииДокументации] = []
        for исходный in узлы where исходный.вид == .файл && исходный.путь.hasPrefix("Документация/") && исходный.путь != "Документация/README.md" {
            let имя = ПрофильОбъединенияДокументации.назначение(исходный.путь)
            guard let целевой = поПути[Data(имя.utf8)], целевой.вид == .файл else { continue }
            var доказана = исходный.режим == целевой.режим && исходный.байты == целевой.байты
            if (исходный.путь as NSString).pathExtension.lowercased() == "md" {
                do {
                    let доказательство = try ДоказательствоАдреснойКопииДокументации.построить(исходный: исходный, целевой: целевой,
                        отображения: отображения, пространство: пространство)
                    доказательства.append(доказательство); доказана = true
                } catch { доказана = false } // Исходник сохраняется; профиль выводит occupied/HOLD.
            }
            if доказана {
                каноны.append(.init(исходный: исходный.путь, целевой: целевой.путь, исходныйSHA256: хэшПутей(исходный.байты),
                    целевойSHA256: хэшПутей(целевой.байты), основание: "вычисленное равенство nonURI и разрешённых будущих bytes/targets",
                    подготовленнаяЦель: целевой.объект.isEmpty))
            }
        }
        var слияние: РешениеСлиянияREADMEДокументации?
        if вход.объединитьREADME, let исходный = поПути[Data("Документация/README.md".utf8)], let целевой = поПути[Data("dokumentaciya/README.md".utf8)] {
            слияние = .init(исходныйSHA256: хэшПутей(исходный.байты), целевойSHA256: хэшПутей(целевой.байты),
                основание: "явное P4 решение сохранить обе функции README; finite body union", подготовленнаяЦель: целевой.объект.isEmpty)
        }
        let основа = ОсноваОбщейМиграции(корневаяЗадача: вход.корневаяЗадача, владелец: вход.владелец, ветка: ветка,
            коммит: коммит, дерево: try ПримитивыДокументации.текстГит(корень, ["rev-parse", "HEAD^{tree}"]), индексSHA256: хэшПутей(логическийИндекс))
        let план = try ПрофильОбъединенияДокументации.построить(основа: основа, ожидаемаяОснова: основа, узлы: узлы,
            пространство: пространство, индексДо: логическийИндекс, каноны: каноны,
            входящие: вход.входящие.map { .init(путь: $0.путь, байты: $0.байты, sha256: $0.sha256) },
            времяСвежести: вход.времяСвежести, слияниеREADME: слияние)
        // Независимый post-fence. Это осознанный повторный снимок, не повтор эффекта.
        try ПримитивыДокументации.требовать(try ПримитивыДокументации.состав(корень) == состав.0
            && ПримитивыДокументации.пространство(корень, индекс: логическийИндекс, узлыDocs: узлы.map(\.путь)) == пространство
            && ПримитивыДокументации.гит(корень, ["ls-files", "--stage", "-z"]) == логическийИндекс
            && ПримитивыДокументации.прочитать(каталогGit.appendingPathComponent("index"), предел: 67_108_864).0 == физическийИндекс.0
            && ПримитивыДокументации.текстГит(корень, ["rev-parse", "HEAD"]) == коммит
            && ПримитивыДокументации.текстГит(корень, ["symbolic-ref", "HEAD"]) == ветка, "дрейф-производителя-плана")
        try ПримитивыДокументации.требовать(try ПримитивыДокументации.пространство(корень, индекс: логическийИндекс, узлыDocs: узлы.map(\.путь)) == пространство,
            "поздний-дрейф-namespace-производителя")
        var режимы: [String: UInt32] = [:]
        for узел in узлы {
            guard let режим = состав.2[узел.путь.precomposedStringWithCanonicalMapping] else { throw ОтказАдаптераДокументации.условие("нет-POSIX-mode-снимка") }
            режимы[узел.путь] = режим
        }
        let пакет = ПакетИсполненияДокументации(корень: корень.path, каталогGit: каталогGit.path, план: план,
            физическийИндексДо: физическийИндекс.0, режимИндекса: физическийИндекс.1, режимыУзлов: режимы,
            доказательстваКопий: доказательства.sorted { порядокПутей($0.исходный, $1.исходный) }, времяЖурнала: вход.времяЖурнала)
        try СегментныйЖурналДокументации.проверитьЁмкость(байтПакета: байтыПлана(пакет).count, шагов: план.шаги.count)
        return пакет
    }
    static func применить(_ пакет: ПакетИсполненияДокументации, допуск: ДопускИсполненияДокументации,
        неисправность: ((String, Int) throws -> Void)? = nil) throws -> КвитанцияОбъединенияДокументации {
        guard пакет.план.препятствия.isEmpty else {
            return try .init(планSHA256: хэшПутей(байтыПлана(пакет.план)), исход: .удержано, подтверждённыйПрефикс: 0, причина: "есть-препятствия-плана")
        }
        let журнал = try СегментныйЖурналДокументации(пакет: пакет, допуск: допуск)
        let среда = try СистемныеЭффектыДокументации(пакет: пакет, допуск: допуск)
        среда.журнал = журнал; среда.неисправность = неисправность
        журнал.снятьСвидетельство = { [weak среда] номер in
            guard let среда else { throw ОтказАдаптераДокументации.условие("потерян-file-adapter") }
            return try среда.свидетельство(номер)
        }
        журнал.послеПодтверждения = { [weak среда] номер in try среда?.очиститьРезервы(номер) }
        return try ПрименениеОбъединенияДокументации.выполнить(пакет.план,
            ожидаемыйSHA256: хэшПутей(байтыПлана(пакет.план)), журнал: журнал, среда: среда)
    }
}

// Отдельный конечный вход; shared fum-puti/legacy fixed9 не активируется.
// Компиляция и вызов требуют собственного будущего допуска ROOT.
#if ФУМ_ПАКЕТ_ДОКУМЕНТАЦИИ_КОМАНДА
private struct ВходКомандыПакетаДокументации: Codable {
    var режим: String
    var корень: String
    var файлПакета: String
    var пакетSHA256: String?
    var планирование: ВходПланированияДокументации?
    var допуск: ДопускИсполненияДокументации?
}
@main struct КомандаПакетаДокументации {
    static func main() {
        do {
            let данные = try FileHandle.standardInput.read(upToCount: 1_048_577) ?? Data()
            try ПримитивыДокументации.требовать(данные.count <= 1_048_576, "предел-stdin-команды")
            let вход = try JSONDecoder().decode(ВходКомандыПакетаДокументации.self, from: данные)
            let адрес = URL(fileURLWithPath: вход.файлПакета)
            if вход.режим == "план" {
                guard let планирование = вход.планирование else { throw ОтказАдаптераДокументации.условие("нет-входа-планирования") }
                let пакет = try ПакетноеОбъединениеДокументации.построить(корень: URL(fileURLWithPath: вход.корень), вход: планирование)
                try ПримитивыДокументации.абсолютныйКаталог(адрес.deletingLastPathComponent(), приватный: true)
                let результат = try байтыПлана(пакет)
                try ПримитивыДокументации.записатьНовый(результат, адрес)
                try FileHandle.standardOutput.write(contentsOf: Data((хэшПутей(результат) + "\n").utf8))
            } else if вход.режим == "применить" {
                guard let допуск = вход.допуск, let ожидаемый = вход.пакетSHA256 else { throw ОтказАдаптераДокументации.условие("нет-отдельного-допуска") }
                let сохранённые = try ПримитивыДокументации.прочитать(адрес, предел: 50_331_648, приватный: true).0
                try ПримитивыДокументации.требовать(хэшПутей(сохранённые) == ожидаемый && ожидаемый == допуск.пакетSHA256, "дрейф-пакета-команды")
                let пакет = try JSONDecoder().decode(ПакетИсполненияДокументации.self, from: сохранённые)
                try ПримитивыДокументации.требовать(try байтыПлана(пакет) == сохранённые && пакет.корень == вход.корень, "другие-байты-или-корень-пакета")
                let квитанция = try ПакетноеОбъединениеДокументации.применить(пакет, допуск: допуск)
                try FileHandle.standardOutput.write(contentsOf: байтыПлана(квитанция))
                if квитанция.исход != .завершено { exit(3) }
            } else { throw ОтказАдаптераДокументации.условие("неизвестный-режим-команды") }
        } catch {
            try? FileHandle.standardError.write(contentsOf: Data("Пакет документации: \(error)\n".utf8)); exit(2)
        }
    }
}
#endif

public actor АдаптерАдресаАгента {
    /// C2 описывает передачу существующей owner/session. create_thread создаёт
    /// дочернюю session и пока не имеет принятого custody-transfer контракта.
    /// Не включать без отдельного контракта, связывающего обе идентичности.
    private static let созданиеДочернейСессииПоддержано = false

    private let считыватель: any СчитывательСостоянияАдресаАгента
    private let источникПина: any ИсточникНезависимогоПинаАдресаАгента
    private let хранилище: any ХранилищеПопытокАдресаАгента
    private let замок: any ЗамокКустодииАдресаАгента
    private let транспорт: any ТранспортСозданияCodexАдресаАгента
    private let наблюдатель: any НаблюдательПервогоХодаАдресаАгента
    private let часы: any ЧасыАдресаАгента

    public init(считыватель: any СчитывательСостоянияАдресаАгента,
                источникПина: any ИсточникНезависимогоПинаАдресаАгента,
                хранилище: any ХранилищеПопытокАдресаАгента,
                замок: any ЗамокКустодииАдресаАгента,
                транспорт: any ТранспортСозданияCodexАдресаАгента,
                наблюдатель: any НаблюдательПервогоХодаАдресаАгента,
                часы: any ЧасыАдресаАгента) {
        self.считыватель = считыватель
        self.источникПина = источникПина
        self.хранилище = хранилище
        self.замок = замок
        self.транспорт = транспорт
        self.наблюдатель = наблюдатель
        self.часы = часы
    }

    public func выполнить(
        команду: КомандаСозданияCodexАдресаАгента,
        идентификаторПопытки: String
    ) async -> РезультатАдаптераАдресаАгента {
        let байтыКоманды: Data
        do {
            guard UUID(uuidString: идентификаторПопытки) != nil else {
                throw ОшибкаАдаптераАдресаАгента.недопустимоеНамерение
            }
            байтыКоманды = try команду.сырыеБайты()
            guard !байтыКоманды.isEmpty, байтыКоманды.count <= 65_536,
                  !команду.запрос.isEmpty, !команду.модель.isEmpty, !команду.усилие.isEmpty,
                  !команду.заголовок.isEmpty else {
                throw ОшибкаАдаптераАдресаАгента.недопустимоеНамерение
            }
        } catch {
            return результат(.заблокированоДоНамерения, "неверная-команда-или-ID", идентификаторПопытки, nil, nil)
        }

        guard Self.созданиеДочернейСессииПоддержано else {
            return результат(
                .неизвестно,
                "создание-дочерней-сессии-без-принятого-контракта-передачи-владения",
                идентификаторПопытки,
                nil,
                nil
            )
        }

        do {
            return try await замок.подЗамком { [self] in
                try await выполнитьПодЗамком(
                    команду: команду,
                    байтыКоманды: байтыКоманды,
                    идентификаторПопытки: идентификаторПопытки
                )
            }
        } catch {
            return результат(.неизвестно, "ошибка-замка-или-чтения", идентификаторПопытки, nil, nil)
        }
    }

    private func выполнитьПодЗамком(
        команду: КомандаСозданияCodexАдресаАгента,
        байтыКоманды: Data,
        идентификаторПопытки: String
    ) async throws -> РезультатАдаптераАдресаАгента {
        var потреблениеПопыткиНачато = false
        let командаSHA = хэшПутей(байтыКоманды)
        let начальноеНаблюдение: НаблюдениеРабочегоСостоянияАдресаАгента
        let план: ПланАдресаАгента
        do {
            начальноеНаблюдение = try await считыватель.считать()
            guard начальноеНаблюдение.custodyДействует == .да else {
                return результат(.заблокированоДоНамерения, "нет-подтверждённого-custody", идентификаторПопытки, nil, nil)
            }
            план = try начальноеНаблюдение.построитьПлан()
            try проверитьКоманду(команду, план: план)
            guard план.можноПодготовитьНамерение else {
                return результат(.заблокированоДоНамерения, "план-не-разрешает-намерение", идентификаторПопытки, план.отпечаток, nil)
            }
        } catch {
            return результат(.заблокированоДоНамерения, "неверный-план-или-адрес", идентификаторПопытки, nil, nil)
        }

        let исходныйЖурнал: СнимокСырогоЖурналаАдресаАгента
        let история: ИсторияПопытокАдресаАгента
        let записи: [ЗаписьЖурналаПопыткиАдресаАгента]
        do {
            исходныйЖурнал = try await хранилище.прочитатьЖурнал()
            (история, записи) = try разобратьЖурнал(исходныйЖурнал)
        } catch {
            return результат(.заблокированоДоНамерения, "история-неполна-или-повреждена", идентификаторПопытки, план.отпечаток, nil)
        }

        if let прежняя = записи.first(where: { $0.намерение.идентификатор == идентификаторПопытки }) {
            return await восстановитьБезПовтора(
                прежняя: прежняя,
                план: план,
                команда: команду,
                байтыКоманды: байтыКоманды,
                идентификаторПопытки: идентификаторПопытки
            )
        }

        do {
            let пин = try await источникПина.получить(
                план: план,
                командаSHA256: командаSHA,
                историяSHA256: история.источникSHA256,
                маршрут: начальноеНаблюдение.маршрут
            )
            try проверитьПроисхождениеПина(
                пин,
                наблюдение: начальноеНаблюдение,
                план: план
            )
            let опоры = try ЯдроАдресаАгента.опоры(
                план: план,
                источникПолномочия: пин.источник,
                полномочиеSHA256: пин.полномочиеSHA256
            )
            let проверенныйPermit = try ЯдроАдресаАгента.проверитьДопуск(
                байты: пин.байты,
                утверждённыйSHA256: пин.утверждённыйSHA256,
                опоры: опоры,
                план: план,
                времяСекундUTC: часы.сейчасСекундUTC()
            )

            // Декодирование разрешено только после независимой hash-проверки ядром.
            let permit = try JSONDecoder().decode(ДопускЭффектаАдресаАгента.self, from: пин.байты)
            try сверитьМаршрут(начальноеНаблюдение.маршрут, permit: permit)

            // Последнее чтение до intent идёт после всех async источников.
            // CAS остаётся следующим внешним ожиданием после локальной сборки intent.
            let наблюдениеПередНамерением = try await считыватель.считать()
            guard наблюдениеПередНамерением.custodyДействует == .да else {
                return результат(.заблокированоДоНамерения, "custody-неподтверждён-перед-намерением", идентификаторПопытки, план.отпечаток, nil)
            }
            let планПередНамерением = try наблюдениеПередНамерением.построитьПлан()
            try сверитьМаршрут(наблюдениеПередНамерением.маршрут, permit: permit)
            try проверитьПроисхождениеПина(пин, наблюдение: наблюдениеПередНамерением, план: планПередНамерением)
            guard планПередНамерением == план,
                  наблюдениеПередНамерением.маршрут == начальноеНаблюдение.маршрут else {
                return результат(.заблокированоДоНамерения, "дрейф-плана-или-маршрута-перед-намерением", идентификаторПопытки, план.отпечаток, nil)
            }
            try проверитьКоманду(команду, план: планПередНамерением)

            let намерение = try ЯдроАдресаАгента.намерение(
                план: план,
                свежийПлан: планПередНамерением,
                идентификатор: идентификаторПопытки,
                наблюдение: наблюдениеПередНамерением.ожидалось,
                история: история,
                допуск: проверенныйPermit,
                времяСекундUTC: часы.сейчасСекундUTC()
            )

            let строкаНамерения = try сериализовать(
                .init(намерение: намерение, командаSHA256: командаSHA)
            )
            // Ошибка CAS с неизвестным исходом также запрещает повторный effect.
            потреблениеПопыткиНачато = true
            let потреблённыйЖурнал = try await хранилище.потребитьПопытку(
                строка: строкаНамерения,
                ожидаемыйЖурналSHA256: история.источникSHA256
            )
            try проверитьПотребление(
                исходный: исходныйЖурнал,
                новый: потреблённыйЖурнал,
                строка: строкаНамерения,
                намерение: намерение,
                командаSHA256: командаSHA
            )

            // Намерение уже долговечно потреблено. Любой последующий сбой
            // завершает попытку UNKNOWN и никогда не возвращается к transport.
            let свежееНаблюдение = try await считыватель.считать()
            let свежийПлан = try свежееНаблюдение.построитьПлан()
            try сверитьМаршрут(свежееНаблюдение.маршрут, permit: permit)
            guard свежееНаблюдение.custodyДействует == .да else {
                return результат(.неизвестно, "custody-утрачен-после-намерения", идентификаторПопытки, план.отпечаток, nil)
            }
            let свежийЖурнал = try await хранилище.прочитатьЖурнал()
            guard свежийЖурнал.границаПолна == .да,
                  свежийЖурнал.байты == потреблённыйЖурнал.байты,
                  хэшПутей(свежийЖурнал.байты) == хэшПутей(потреблённыйЖурнал.байты) else {
                return результат(.неизвестно, "сырая-история-изменилась-перед-эффектом", идентификаторПопытки, план.отпечаток, nil)
            }
            let свежийПин = try await источникПина.получить(
                план: свежийПлан,
                командаSHA256: командаSHA,
                историяSHA256: намерение.историяSHA256,
                маршрут: свежееНаблюдение.маршрут
            )
            try проверитьПроисхождениеПина(свежийПин, наблюдение: свежееНаблюдение, план: свежийПлан)
            try проверитьСовпадениеПинов(пин, свежийПин)
            try ЯдроАдресаАгента.проверитьПередЭффектом(
                допуск: проверенныйPermit,
                план: план,
                свежийПлан: свежийПлан,
                намерение: намерение,
                команда: байтыКоманды,
                времяСекундUTC: часы.сейчасСекундUTC()
            )
            try проверитьКоманду(команду, план: свежийПлан)

            let ответ: Data
            do {
                // Ровно один вызов. Ни UUID попытки, ни idempotency key в API нет.
                ответ = try await транспорт.вызватьОдинРаз(сырыеБайтыКоманды: байтыКоманды)
            } catch {
                try await сохранитьНеизвестность(идентификаторПопытки, намерение, командаSHA, nil)
                return результат(.неизвестно, "ответ-транспорта-потерян", идентификаторПопытки, план.отпечаток, nil)
            }

            let сохранённыйОтвет = try await хранилище.сохранитьСыройОтвет(ответ, дляПопытки: идентификаторПопытки)
            guard сохранённыйОтвет.байты == ответ,
                  сохранённыйОтвет.sha256 == хэшПутей(ответ),
                  !ответ.isEmpty, ответ.count <= 65_536 else {
                try await сохранитьНеизвестность(идентификаторПопытки, намерение, командаSHA, nil)
                return результат(.неизвестно, "сырой-ответ-не-подтверждён", идентификаторПопытки, план.отпечаток, nil)
            }

            guard let разобранныйID = разобратьID(ответ),
                  разобранныйID.hostID == начальноеНаблюдение.контекст.сессия.hostID else {
                let квитанция = хэшПутей(ответ)
                try await сохранитьНеизвестность(идентификаторПопытки, намерение, командаSHA, квитанция)
                return результат(.неизвестно, "ID-ответа-неполны-или-конфликтуют", идентификаторПопытки, план.отпечаток, квитанция)
            }

            let сыроеНаблюдение: Data
            do {
                сыроеНаблюдение = try await наблюдатель.считать(
                    идентификаторЗадачи: разобранныйID.threadID,
                    hostID: разобранныйID.hostID,
                    план: план
                )
            } catch {
                let квитанция = хэшПутей(ответ)
                try await сохранитьНеизвестность(идентификаторПопытки, намерение, командаSHA, квитанция)
                return результат(.неизвестно, "повторное-наблюдение-недоступно", идентификаторПопытки, план.отпечаток, квитанция)
            }

            let сохранённоеНаблюдение = try await хранилище.сохранитьСыроеНаблюдение(
                сыроеНаблюдение,
                дляПопытки: идентификаторПопытки
            )
            guard сохранённоеНаблюдение.байты == сыроеНаблюдение,
                  сохранённоеНаблюдение.sha256 == хэшПутей(сыроеНаблюдение) else {
                let квитанция = хэшПутей(ответ)
                try await сохранитьНеизвестность(идентификаторПопытки, намерение, командаSHA, квитанция)
                return результат(.неизвестно, "сырое-наблюдение-не-подтверждено", идентификаторПопытки, план.отпечаток, квитанция)
            }

            let наблюдение = try JSONDecoder().decode(НаблюдениеПервогоХодаАдресаАгента.self, from: сыроеНаблюдение)
            try проверитьНаблюдение(
                наблюдение,
                идентификаторЗадачи: разобранныйID.threadID,
                hostID: разобранныйID.hostID,
                команда: команду,
                план: план
            )
            let квитанция = хэшПутей(ответ)
            let исход = ИсходАдресаАгента(
                идентификаторНамерения: намерение.идентификатор,
                отпечатокПлана: план.отпечаток,
                вид: .применено,
                квитанцияSHA256: квитанция,
                наблюдение: наблюдение.снимок
            )
            let строкаИсхода = try сериализовать(
                .init(намерение: намерение, командаSHA256: командаSHA,
                      квитанцияSHA256: квитанция, исход: .применено)
            )
            let журналИсхода = try await хранилище.добавитьИсход(
                строка: строкаИсхода,
                дляПопытки: идентификаторПопытки
            )
            guard журналИсхода.границаПолна == .да else {
                return результат(.неизвестно, "терминальная-граница-журнала-неизвестна", идентификаторПопытки, план.отпечаток, квитанция)
            }
            let восстановление = try ЯдроАдресаАгента.восстановить(
                план: план, намерение: намерение, исход: исход, наблюдение: наблюдение.снимок
            )
            guard восстановление.состояние == .подтверждено,
                  восстановление.повторМутацииРазрешён == false else {
                return результат(.неизвестно, "ядро-не-подтвердило-переход", идентификаторПопытки, план.отпечаток, квитанция)
            }
            return результат(.подтверждено, "совпали-квитанция-первый-ход-и-управляемый-W", идентификаторПопытки, план.отпечаток, квитанция)
        } catch ОшибкаАдаптераАдресаАгента.неполныйЖурнал {
            if потреблениеПопыткиНачато {
                return результат(.неизвестно, "ошибка-после-попытки-потребления", идентификаторПопытки, план.отпечаток, nil)
            }
            return результат(.заблокированоДоНамерения, "история-неполна", идентификаторПопытки, план.отпечаток, nil)
        } catch {
            if потреблениеПопыткиНачато {
                return результат(.неизвестно, "ошибка-после-попытки-потребления", идентификаторПопытки, план.отпечаток, nil)
            }
            // Ошибка до подтверждённого consumption не разрешает transport.
            return результат(.заблокированоДоНамерения, "guard-не-пройден", идентификаторПопытки, план.отпечаток, nil)
        }
    }

    private func восстановитьБезПовтора(
        прежняя: ЗаписьЖурналаПопыткиАдресаАгента,
        план: ПланАдресаАгента,
        команда: КомандаСозданияCodexАдресаАгента,
        байтыКоманды: Data,
        идентификаторПопытки: String
    ) async -> РезультатАдаптераАдресаАгента {
        guard прежняя.командаSHA256 == хэшПутей(байтыКоманды),
              прежняя.намерение.отпечатокПлана == план.отпечаток else {
            return результат(.неизвестно, "повторный-ID-с-другим-намерением", идентификаторПопытки, план.отпечаток, прежняя.квитанцияSHA256)
        }
        do {
            guard let сохранённая = try await хранилище.прочитатьПопытку(идентификаторПопытки),
                  сохранённая.намерение == прежняя.намерение,
                  сохранённая.командаSHA256 == хэшПутей(байтыКоманды),
                  let ответ = сохранённая.сырыеБайтыОтвета,
                  let квитанция = сохранённая.квитанцияSHA256,
                  квитанция == хэшПутей(ответ),
                  let сыроеНаблюдение = сохранённая.сырыеБайтыНаблюдения else {
                return результат(.неизвестно, "попытка-уже-потреблена-без-полного-readback", идентификаторПопытки, план.отпечаток, прежняя.квитанцияSHA256)
            }
            guard let id = разобратьID(ответ) else {
                return результат(.неизвестно, "сохранённый-ID-ответа-неполон", идентификаторПопытки, план.отпечаток, квитанция)
            }
            let observation = try JSONDecoder().decode(НаблюдениеПервогоХодаАдресаАгента.self, from: сыроеНаблюдение)
            try проверитьНаблюдение(
                observation,
                идентификаторЗадачи: id.threadID,
                hostID: id.hostID,
                команда: команда,
                план: план
            )
            let исход = ИсходАдресаАгента(
                идентификаторНамерения: прежняя.намерение.идентификатор,
                отпечатокПлана: план.отпечаток,
                вид: сохранённая.исход == .безЭффекта ? .безЭффекта :
                    (сохранённая.исход == .неизвестно ? .неизвестно : .применено),
                квитанцияSHA256: квитанция,
                наблюдение: observation.снимок
            )
            let восстановление = try ЯдроАдресаАгента.восстановить(
                план: план, намерение: прежняя.намерение, исход: исход, наблюдение: observation.снимок
            )
            switch восстановление.состояние {
            case .подтверждено:
                return результат(.подтверждено, "восстановлено-по-сохранённой-квитанции", идентификаторПопытки, план.отпечаток, квитанция)
            case .завершеноБезЭффекта:
                return результат(.завершеноБезЭффекта, "восстановлен-терминальный-исход-без-эффекта", идентификаторПопытки, план.отпечаток, квитанция)
            default:
                return результат(.неизвестно, "сохранённая-попытка-не-согласована", идентификаторПопытки, план.отпечаток, квитанция)
            }
        } catch {
            return результат(.неизвестно, "ошибка-восстановления-без-повтора", идентификаторПопытки, план.отпечаток, прежняя.квитанцияSHA256)
        }
    }

    private func сохранитьНеизвестность(
        _ идентификатор: String,
        _ намерение: НамерениеАдресаАгента,
        _ командаSHA: String,
        _ квитанцияSHA: String?
    ) async throws {
        let строка = try сериализовать(
            .init(намерение: намерение, командаSHA256: командаSHA,
                  квитанцияSHA256: квитанцияSHA, исход: .неизвестно)
        )
        _ = try await хранилище.добавитьИсход(строка: строка, дляПопытки: идентификатор)
    }

    private func результат(
        _ состояние: СостояниеАдаптераАдресаАгента,
        _ причина: String,
        _ идентификатор: String,
        _ план: String?,
        _ квитанция: String?
    ) -> РезультатАдаптераАдресаАгента {
        .init(состояние: состояние, причина: причина, идентификаторПопытки: идентификатор,
              отпечатокПлана: план, квитанцияSHA256: квитанция)
    }

    private func проверитьКоманду(_ команда: КомандаСозданияCodexАдресаАгента, план: ПланАдресаАгента) throws {
        guard команда.цель.тип == "project",
              команда.цель.идентификаторПроекта == план.контекст.сессия.projectID,
              команда.цель.среда.тип == "worktree",
              команда.цель.среда.исходноеСостояние.тип == "branch",
              команда.цель.среда.исходноеСостояние.имяВетки == план.цель.полныйRef,
              команда.цель.среда.исходноеСостояние.еслиВеткиНет == "error" else {
            throw ОшибкаАдаптераАдресаАгента.недопустимоеНамерение
        }
    }

    private func проверитьПроисхождениеПина(
        _ пин: НезависимыйПинДопускаАдресаАгента,
        наблюдение: НаблюдениеРабочегоСостоянияАдресаАгента,
        план: ПланАдресаАгента
    ) throws {
        guard !пин.байты.isEmpty, пин.байты.count <= 65_536,
              !пин.источник.isEmpty, !пин.путьИсточника.isEmpty,
              шестнадцатеричный(пин.объектИсточника, 40),
              шестнадцатеричный(пин.утверждённыйSHA256, 64),
              шестнадцатеричный(пин.полномочиеSHA256, 64),
              пин.принятыйM == план.контекст.принятыйM,
              пин.проверяющийSHA256 == план.контекст.проверяющийSHA256 else {
            throw ОшибкаАдаптераАдресаАгента.неправильныйPermit
        }
        switch наблюдение.маршрут.состояние {
        case .пройден:
            break
        case .отказ:
            guard пин.авторитет == .корень else { throw ОшибкаАдаптераАдресаАгента.неправильныйPermit }
        case .неизвестно:
            throw ОшибкаАдаптераАдресаАгента.неправильныйPermit
        }
    }

    private func проверитьСовпадениеПинов(
        _ исходный: НезависимыйПинДопускаАдресаАгента,
        _ свежий: НезависимыйПинДопускаАдресаАгента
    ) throws {
        guard исходный.байты == свежий.байты,
              исходный.утверждённыйSHA256 == свежий.утверждённыйSHA256,
              исходный.авторитет == свежий.авторитет,
              исходный.источник == свежий.источник,
              исходный.объектИсточника == свежий.объектИсточника,
              исходный.путьИсточника == свежий.путьИсточника,
              исходный.полномочиеSHA256 == свежий.полномочиеSHA256,
              исходный.принятыйM == свежий.принятыйM,
              исходный.проверяющийSHA256 == свежий.проверяющийSHA256 else {
            throw ОшибкаАдаптераАдресаАгента.дрейф
        }
    }

    private func сверитьМаршрут(
        _ маршрут: НаблюдениеМаршрутаАдресаАгента,
        permit: ДопускЭффектаАдресаАгента
    ) throws {
        guard маршрут.состояние == permit.маршрут,
              маршрут.причина.utf8.elementsEqual(permit.причинаМаршрута.utf8),
              маршрут.квитанцияSHA256 == permit.квитанцияМаршрутаSHA256 else {
            throw ОшибкаАдаптераАдресаАгента.дрейф
        }
        switch маршрут.состояние {
        case .пройден:
            guard permit.исключениеROOT == nil else { throw ОшибкаАдаптераАдресаАгента.неправильныйPermit }
        case .отказ:
            guard permit.исключениеROOT != nil else { throw ОшибкаАдаптераАдресаАгента.неправильныйPermit }
        case .неизвестно:
            throw ОшибкаАдаптераАдресаАгента.неправильныйPermit
        }
    }

    private func проверитьНаблюдение(
        _ наблюдение: НаблюдениеПервогоХодаАдресаАгента,
        идентификаторЗадачи: String,
        hostID: String,
        команда: КомандаСозданияCodexАдресаАгента,
        план: ПланАдресаАгента
    ) throws {
        let отпечатокХода = try команда.отпечатокПервогоХода()
        guard let привязкаЦели = план.цель.привязка,
              идентичностиНаблюденияАдресаАгентаСогласованы(
                наблюдение,
                внешнийThreadID: идентификаторЗадачи,
                внешнийHostID: hostID,
                ожидаемаяПривязка: привязкаЦели,
                ожидаемыйСнимок: план.цель
              ) else {
            throw ОшибкаАдаптераАдресаАгента.неверноеНаблюдение
        }
        guard наблюдение.схема == "fum.native-first-turn-observation.1",
              наблюдение.идентификаторЗадачи == идентификаторЗадачи,
              наблюдение.hostID == hostID,
              наблюдение.hostID == план.контекст.сессия.hostID,
              наблюдение.родительThreadID == план.контекст.сессия.threadID,
              наблюдение.родительAttachmentID == план.контекст.сессия.clientID,
              наблюдение.projectID == команда.цель.идентификаторПроекта,
              наблюдение.первыйХодSHA256 == отпечатокХода,
              наблюдение.модель == команда.модель,
              наблюдение.усилие == команда.усилие,
              наблюдение.полныйRef == план.цель.полныйRef,
              наблюдение.физическийW == план.цель.физическийW,
              наблюдение.начальныйHEAD == план.цель.HEAD,
              наблюдение.индексSHA256 == план.цель.индексSHA256,
              !наблюдение.attachmentID.isEmpty,
              наблюдение.управляемоеДерево == .да,
              наблюдение.снимок.свойства.чистое == .да,
              наблюдение.снимок.физическийW == план.цель.физическийW,
              наблюдение.снимок.полныйRef == план.цель.полныйRef,
              наблюдение.снимок.HEAD == план.цель.HEAD,
              наблюдение.снимок.индексSHA256 == план.цель.индексSHA256 else {
            throw ОшибкаАдаптераАдресаАгента.неверноеНаблюдение
        }
        try ЯдроАдресаАгента.проверитьПлан(план)
    }

    private func проверитьПотребление(
        исходный: СнимокСырогоЖурналаАдресаАгента,
        новый: СнимокСырогоЖурналаАдресаАгента,
        строка: Data,
        намерение: НамерениеАдресаАгента,
        командаSHA256: String
    ) throws {
        guard исходный.границаПолна == .да, новый.границаПолна == .да,
              новый.байты == исходный.байты + строка,
              хэшПутей(исходный.байты) != хэшПутей(новый.байты) else {
            throw ОшибкаАдаптераАдресаАгента.неизвестнаяПопытка
        }
        let (история, записи) = try разобратьЖурнал(новый)
        guard история.полна == .да,
              записи.contains(where: {
                  $0.намерение == намерение && $0.командаSHA256 == командаSHA256
                      && $0.квитанцияSHA256 == nil && $0.исход == nil
              }) else {
            throw ОшибкаАдаптераАдресаАгента.неизвестнаяПопытка
        }
    }

    private func разобратьЖурнал(
        _ снимок: СнимокСырогоЖурналаАдресаАгента
    ) throws -> (ИсторияПопытокАдресаАгента, [ЗаписьЖурналаПопыткиАдресаАгента]) {
        guard снимок.границаПолна == .да,
              снимок.байты.count <= 8 * 1024 * 1024,
              снимок.байты.isEmpty || снимок.байты.last == 10 else {
            throw ОшибкаАдаптераАдресаАгента.неполныйЖурнал
        }
        var последние: [String: ЗаписьЖурналаПопыткиАдресаАгента] = [:]
        if !снимок.байты.isEmpty {
            let содержимое = снимок.байты.dropLast()
            let строки = содержимое.split(separator: 10, omittingEmptySubsequences: false)
            guard строки.count <= 4096, строки.allSatisfy({ !$0.isEmpty && $0.count <= 65_536 }) else {
                throw ОшибкаАдаптераАдресаАгента.неполныйЖурнал
            }
            for сыраяСтрока in строки {
                let запись = try JSONDecoder().decode(ЗаписьЖурналаПопыткиАдресаАгента.self, from: Data(сыраяСтрока))
                guard запись.схема == "fum.журнал-попыток-адреса-агента.1",
                      UUID(uuidString: запись.намерение.идентификатор) != nil,
                      запись.намерение.версия == ЯдроАдресаАгента.версия,
                      шестнадцатеричный(запись.намерение.отпечатокПлана, 64),
                      шестнадцатеричный(запись.намерение.допускSHA256, 64),
                      шестнадцатеричный(запись.намерение.историяSHA256, 64),
                      шестнадцатеричный(запись.командаSHA256, 64),
                      запись.квитанцияSHA256.map({ шестнадцатеричный($0, 64) }) ?? true else {
                    throw ОшибкаАдаптераАдресаАгента.неполныйЖурнал
                }
                if let прежняя = последние[запись.намерение.идентификатор] {
                    guard прежняя.намерение == запись.намерение,
                          прежняя.командаSHA256 == запись.командаSHA256 else {
                        throw ОшибкаАдаптераАдресаАгента.неполныйЖурнал
                    }
                }
                последние[запись.намерение.идентификатор] = запись
            }
        }
        let записи = последние.values.sorted {
            $0.намерение.идентификатор.utf8.lexicographicallyPrecedes($1.намерение.идентификатор.utf8)
        }
        guard Set(записи.map { $0.намерение.отпечатокПлана }).count == записи.count else {
            throw ОшибкаАдаптераАдресаАгента.неполныйЖурнал
        }
        let история = ИсторияПопытокАдресаАгента(
            полна: .да,
            источникSHA256: хэшПутей(снимок.байты),
            намерения: записи.map(\.намерение)
        )
        return (история, записи)
    }

    private func сериализовать(_ запись: ЗаписьЖурналаПопыткиАдресаАгента) throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(запись) + Data([10])
    }
}

/// Внешние Native IDs должны описывать ту же session, что и вложенный typed snapshot.
/// Child thread/attachment не являются алиасами parent binding из ядра C2.
func идентичностиНаблюденияАдресаАгентаСогласованы(
    _ наблюдение: НаблюдениеПервогоХодаАдресаАгента,
    внешнийThreadID: String,
    внешнийHostID: String,
    ожидаемаяПривязка: ПривязкаСессииАгента,
    ожидаемыйСнимок: СнимокАдресаАгента
) -> Bool {
    наблюдение.идентификаторЗадачи == внешнийThreadID
        && наблюдение.hostID == внешнийHostID
        && наблюдение.идентификаторЗадачи == ожидаемаяПривязка.threadID
        && наблюдение.hostID == ожидаемаяПривязка.hostID
        && наблюдение.родительThreadID == ожидаемаяПривязка.threadID
        && наблюдение.родительAttachmentID == ожидаемаяПривязка.clientID
        && наблюдение.attachmentID == ожидаемаяПривязка.clientID
        && наблюдение.снимок.привязка == ожидаемаяПривязка
        && наблюдение.снимок == ожидаемыйСнимок
}

private func разобратьID(_ байты: Data) -> РазобранныйIDCodexАдреса? {
    guard !байты.isEmpty, байты.count <= 65_536,
          let объект = try? JSONSerialization.jsonObject(with: байты) else { return nil }
    var threadIDs: Set<String> = []
    var clientIDs: Set<String> = []
    var hostIDs: Set<String> = []
    var естьОшибка = false

    func обход(_ значение: Any) {
        if let словарь = значение as? [String: Any] {
            if (словарь["isError"] as? Bool) == true { естьОшибка = true }
            if let значение = словарь["threadId"] as? String, !значение.isEmpty { threadIDs.insert(значение) }
            if let значение = словарь["clientThreadId"] as? String, !значение.isEmpty { clientIDs.insert(значение) }
            if let значение = словарь["hostId"] as? String, !значение.isEmpty { hostIDs.insert(значение) }
            for (ключ, дочернее) in словарь {
                if ключ == "text", let текст = дочернее as? String, let данные = текст.data(using: .utf8),
                   let JSON = try? JSONSerialization.jsonObject(with: данные) {
                    обход(JSON)
                } else if ключ == "structuredContent" || ключ == "content" || ключ == "result" {
                    обход(дочернее)
                }
            }
        } else if let массив = значение as? [Any] {
            for элемент in массив { обход(элемент) }
        }
    }
    обход(объект)

    guard !естьОшибка, threadIDs.count == 1, clientIDs.count <= 1, hostIDs.count == 1,
          let threadID = threadIDs.first, let hostID = hostIDs.first,
          clientIDs.isEmpty || clientIDs.first == threadID else { return nil }
    return РазобранныйIDCodexАдреса(threadID: threadID, hostID: hostID)
}

private func шестнадцатеричный(_ значение: String, _ длина: Int) -> Bool {
    значение.utf8.count == длина && значение.utf8.allSatisfy {
        (48...57).contains($0) || (97...102).contains($0)
    }
}

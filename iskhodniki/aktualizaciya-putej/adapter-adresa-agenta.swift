/// Точное содержимое команды, по которому независимый источник выдаёт permit.
/// Transport не получает UUID попытки: публичный create_thread его не принимает.
public struct КомандаСозданияCodexАдресаАгента: Codable, Equatable, Sendable {
    public let запрос: String
    public let цель: ЦельCodexАдресаАгента
    public let модель: String
    public let усилие: String
    public let заголовок: String

    public init(запрос: String, цель: ЦельCodexАдресаАгента, модель: String, усилие: String, заголовок: String) {
        self.запрос = запрос
        self.цель = цель
        self.модель = модель
        self.усилие = усилие
        self.заголовок = заголовок
    }

    enum CodingKeys: String, CodingKey {
        case запрос = "prompt"
        case цель = "target"
        case модель = "model"
        case усилие = "thinking"
        case заголовок = "title"
    }

    public func сырыеБайты() throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(self) + Data([10])
    }

    public func отпечатокПервогоХода() throws -> String {
        let первыйХод = ПервичныйЗапрос(запрос: запрос, модель: модель, усилие: усилие)
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return хэшПутей(try кодировщик.encode(первыйХод))
    }

    private struct ПервичныйЗапрос: Codable {
        let запрос: String
        let модель: String
        let усилие: String
        enum CodingKeys: String, CodingKey {
            case запрос = "prompt"
            case модель = "model"
            case усилие = "thinking"
        }
    }
}


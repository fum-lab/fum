// Диагностический экземпляр принадлежит одному синхронному RO-плану.
// Текущий документ обновляется до работы; поток содержит редкие снимки, не тела.
final class НаблюдениеОднофайловогоПлана {
    private struct Документ: Encodable {
        let номер: Int
        let всего: Int
        let путь: String?
        let хэшПути: String
        let байтыПути: Int
        let хэшДокумента: String?
        let байтыДокумента: Int?
    }
    private struct Кадр: Encodable {
        let схема = "fum.наблюдение-однофайлового-плана.1"
        let фаза: String
        let участок: String?
        let документ: Документ?
        let курсорUTF8: Int?
        let наносекунды: UInt64
        let счётчики: [String: UInt64]
    }
    private let вывод: (Data) throws -> Void
    private let часы: () -> UInt64
    private let пределКадров: Int
    private let пределБайтов: Int
    private let интервал: UInt64
    private var фаза: ФазаНаблюденияПлана = .вход
    private var участок: String?
    private var документ: Документ?
    private var курсор: Int?
    private var значения: [СчётчикНаблюденияПлана: UInt64] = [:]
    private var ошибка: String?
    private var последнееВремя: UInt64 = 0
    private var тики: UInt64 = 0
    private(set) var числоКадров = 0
    private(set) var числоБайтов = 0

    init(пределКадров: Int = 128, пределБайтов: Int = 65_536,
         интервалНс: UInt64 = 6_000_000_000, часы: (() -> UInt64)? = nil,
         вывод: @escaping (Data) throws -> Void) throws {
        try требоватьСсылки((1...128).contains(пределКадров) && (1...65_536).contains(пределБайтов), "неверный-предел-наблюдения")
        self.пределКадров = пределКадров; self.пределБайтов = пределБайтов
        self.интервал = интервалНс; self.вывод = вывод
        let начало = ContinuousClock.now
        self.часы = часы ?? {
            let части = начало.duration(to: ContinuousClock.now).components
            return UInt64(max(0, части.seconds)) * 1_000_000_000 + UInt64(max(0, части.attoseconds) / 1_000_000_000)
        }
    }
    func счётчик(_ вид: СчётчикНаблюденияПлана) -> UInt64 { значения[вид] ?? 0 }
    func проверить() throws {
        if let ошибка { throw ОтказСсылокПакета.условие(ошибка) }
    }
    func этап(_ новая: ФазаНаблюденияПлана, путь: String? = nil, номер: Int = 0,
        всего: Int = 0, хэш: String? = nil, байты: Int? = nil) throws {
        if новая == фаза && числоКадров > 0 { try проверить(); return }
        фаза = новая; участок = nil; документ = nil; курсор = nil
        if let путь { запомнитьДокумент(номер: номер, всего: всего, путь: путь, хэш: хэш, байты: байты) }
        _ = предложить(принудительно: true)
        try проверить()
    }
    func установитьДокумент(номер: Int, всего: Int, путь: String, хэш: String? = nil, байты: Int? = nil) {
        запомнитьДокумент(номер: номер, всего: всего, путь: путь, хэш: хэш, байты: байты)
        _ = предложить(принудительно: false)
    }
    private func запомнитьДокумент(номер: Int, всего: Int, путь: String, хэш: String?, байты: Int?) {
        let адрес = Data(путь.utf8)
        документ = .init(номер: номер, всего: всего, путь: адрес.count <= 128 ? путь : nil,
            хэшПути: хэшПутей(адрес), байтыПути: адрес.count, хэшДокумента: хэш, байтыДокумента: байты)
        участок = nil; курсор = 0
    }
    func установитьУчасток(_ новый: String, курсор: Int = 0) {
        участок = новый; self.курсор = курсор
        _ = предложить(принудительно: false)
    }
    @discardableResult func учесть(_ вид: СчётчикНаблюденияПлана, _ число: Int = 1, курсор: Int? = nil) -> Bool {
        guard ошибка == nil else { return false }
        guard число >= 0 else { ошибка = "неверный-счётчик-наблюдения"; return false }
        let сумма = (значения[вид] ?? 0).addingReportingOverflow(UInt64(число))
        guard !сумма.overflow else { ошибка = "переполнение-счётчика-наблюдения"; return false }
        значения[вид] = сумма.partialValue
        if let курсор { self.курсор = курсор }
        тики &+= 1
        if тики & 4095 == 0 { return предложить(принудительно: false) }
        return true
    }
    private func предложить(принудительно: Bool) -> Bool {
        guard ошибка == nil else { return false }
        let время = часы()
        guard время >= последнееВремя else { ошибка = "дрейф-часов-наблюдения"; return false }
        if !принудительно && (числоКадров == 0 || время - последнееВремя < интервал) { return true }
        guard числоКадров < пределКадров else { ошибка = "предел-кадров-наблюдения"; return false }
        let счётчики = Dictionary(uniqueKeysWithValues: СчётчикНаблюденияПлана.allCases.map { ($0.rawValue, значения[$0] ?? 0) })
        do {
            let кодер = JSONEncoder(); кодер.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
            let байты = try кодер.encode(Кадр(фаза: фаза.rawValue, участок: участок, документ: документ,
                курсорUTF8: курсор, наносекунды: время, счётчики: счётчики)) + Data([10])
            guard байты.count <= 1536 && байты.count <= пределБайтов - числоБайтов else {
                ошибка = "предел-байтов-наблюдения"; return false
            }
            try вывод(байты)
            числоКадров += 1; числоБайтов += байты.count; последнееВремя = время
            return true
        } catch {
            ошибка = "ошибка-вывода-наблюдения"; return false
        }
    }
}

private func требоватьСсылки(
    _ условие: Bool, _ причина: String
) throws {
    if !условие { throw ОтказСсылокПакета.условие(причина) }
}

// Сопоставление имени не подменяет точное совпадение UTF-8.
private enum АдресСсылкиПакета {
    struct Разбор {
        let путь: String?
        let суффикс: String
    }

    static func точно(_ левый: String, _ правый: String) -> Bool {
        левый.utf8.elementsEqual(правый.utf8)
    }

    static func ключ(_ значение: String) -> String {
        значение.precomposedStringWithCanonicalMapping
            .folding(
                options: [.caseInsensitive],
                locale: Locale(identifier: "en_US_POSIX")
            )
            .precomposedStringWithCanonicalMapping
    }

    static func снятьЭкранирование(_ значение: String) -> String {
        let знаки = Array(значение.unicodeScalars)
        var результат = ""
        var номер = 0
        func пунктуация(_ код: UInt32) -> Bool {
            (33...47).contains(код) || (58...64).contains(код)
                || (91...96).contains(код) || (123...126).contains(код)
        }
        while номер < знаки.count {
            if знаки[номер].value == 92,
               номер + 1 < знаки.count,
               пунктуация(знаки[номер + 1].value) {
                номер += 1
            }
            результат.unicodeScalars.append(знаки[номер])
            номер += 1
        }
        return результат
    }

    static func разделить(_ значение: String) -> (String, String) {
        let байты = Array(значение.utf8)
        var косые = 0
        for номер in байты.indices {
            if [35, 63].contains(байты[номер]), косые % 2 == 0 {
                return (
                    String(decoding: байты[..<номер], as: UTF8.self),
                    String(decoding: байты[номер...], as: UTF8.self)
                )
            }
            косые = байты[номер] == 92 ? косые + 1 : 0
        }
        return (значение, "")
    }

    private static func цифра(_ байт: UInt8) -> UInt8? {
        switch байт {
        case 48...57: байт - 48
        case 65...70: байт - 55
        case 97...102: байт - 87
        default: nil
        }
    }

    static func декодировать(_ значение: String, побайтово: Bool = false) throws -> String {
        let вход = Array(значение.utf8)
        var выход: [UInt8] = []
        var номер = 0
        while номер < вход.count {
            if вход[номер] != 37 {
                выход.append(вход[номер])
                номер += 1
                continue
            }
            guard номер + 2 < вход.count,
                  let старшая = цифра(вход[номер + 1]),
                  let младшая = цифра(вход[номер + 2]) else {
                throw ОтказСсылокПакета.условие("неверное-percent-кодирование")
            }
            let байт = старшая * 16 + младшая
            try требоватьСсылки(
                байт != 47 && байт != 92,
                "закодированный-разделитель"
            )
            выход.append(байт)
            номер += 3
        }
        guard let текст = String(bytes: выход, encoding: .utf8) else {
            throw ОтказСсылокПакета.условие("неверный-UTF8-адрес")
        }
        try требоватьСсылки(
            !(побайтово ? текст.utf8.contains(92) : текст.contains("\\"))
                && !текст.unicodeScalars.contains {
                    CharacterSet.controlCharacters.contains($0)
                },
            "небезопасный-адрес"
        )
        let прежние = побайтово ? ИменаПутей.компоненты(значение, сохранятьПустые: true)
            : значение.split(separator: "/", omittingEmptySubsequences: false).map(String.init)
        let новые = побайтово ? ИменаПутей.компоненты(текст, сохранятьПустые: true)
            : текст.split(separator: "/", omittingEmptySubsequences: false).map(String.init)
        try требоватьСсылки(
            прежние.count == новые.count,
            "изменён-разделитель"
        )
        for (прежний, новый) in zip(прежние, новые) {
            try требоватьСсылки(
                !(прежний.contains("%") && (новый == "." || новый == "..")),
                "закодированный-точечный-сегмент"
            )
        }
        return текст
    }

    static func разобрать(
        _ сырое: String, документ: String, побайтово: Bool = false
    ) throws -> Разбор {
        let (сыройПуть, суффикс) = разделить(сырое)
        let путь = снятьЭкранирование(сыройПуть)

        try требоватьСсылки(
            !(побайтово ? ИменаПутей.имеетПрефикс(путь.lowercased(), "file:") : путь.lowercased().hasPrefix("file:"))
                && путь.range(
                    of: #"^[A-Za-z]:"#,
                    options: .regularExpression
                ) == nil,
            "абсолютный-file-или-Windows-адрес"
        )
        if (побайтово ? ИменаПутей.имеетПрефикс(путь, "//") : путь.hasPrefix("//")) || путь.range(
            of: #"^[A-Za-z][A-Za-z0-9+.-]*:"#,
            options: .regularExpression
        ) != nil {
            return Разбор(путь: nil, суффикс: суффикс)
        }

        // HTML entity decoding — самостоятельный адаптер, а не догадка.
        try требоватьСсылки(
            путь.range(
                of: #"&(?:#[0-9]+|#[xX][0-9A-Fa-f]+|[A-Za-z][A-Za-z0-9]*);"#,
                options: .regularExpression
            ) == nil,
            "неподдержанная-сущность-в-локальном-адресе"
        )

        let декодированный = try декодировать(путь, побайтово: побайтово)
        try требоватьСсылки(
            !(побайтово ? декодированный.utf8.first == 47 : декодированный.hasPrefix("/"))
                && декодированный.range(
                    of: #"^[A-Za-z][A-Za-z0-9+.-]*:"#,
                    options: .regularExpression
                ) == nil,
            "абсолютный-или-неоднозначный-адрес"
        )
        if декодированный.isEmpty {
            return Разбор(путь: документ, суффикс: суффикс)
        }

        var части = Array((побайтово ? ИменаПутей.компоненты(документ) : документ.split(separator: "/").map(String.init)).dropLast())
        let входныеЧасти = побайтово ? ИменаПутей.компоненты(декодированный, сохранятьПустые: true)
            : декодированный.split(separator: "/", omittingEmptySubsequences: false).map(String.init)
        for часть in входныеЧасти {
            if часть.isEmpty || часть == "." { continue }
            if часть == ".." {
                try требоватьСсылки(!части.isEmpty, "выход-за-корень")
                части.removeLast()
            } else {
                части.append(String(часть))
            }
        }
        return Разбор(путь: части.joined(separator: "/"), суффикс: суффикс)
    }

    static func закодировать(_ путь: String, угловое: Bool) -> String {
        let безопасные = Set(
            "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789/-._~!$&'*+,;=:@"
                .unicodeScalars
        )
        var итог = ""
        for знак in путь.unicodeScalars {
            if безопасные.contains(знак)
                || (знак.value >= 128 && !знак.properties.isWhitespace)
                || (угловое && знак.value == 32) {
                итог.unicodeScalars.append(знак)
            } else {
                for байт in String(знак).utf8 {
                    итог += String(format: "%%%02X", байт)
                }
            }
        }
        return итог
    }

    static func относительныйПуть(_ цель: String, документ: String, угловое: Bool) -> String {
        let родитель = Array(ИменаПутей.компоненты(документ).dropLast()), части = ИменаПутей.компоненты(цель)
        var общий = 0
        while общий < родитель.count && общий < части.count && точно(родитель[общий], части[общий]) { общий += 1 }
        let относительный = (Array(repeating: "..", count: родитель.count - общий) + части.dropFirst(общий)).joined(separator: "/")
        return закодировать(относительный.isEmpty ? "." : относительный, угловое: угловое)
    }

    static func замена(
        _ адрес: Разбор,
        документ: String,
        пары: [ОтображениеПути],
        угловое: Bool
    ) throws -> String? {
        guard let путь = адрес.путь else { return nil }
        var назначение: String?
        var совпадения = 0
        for пара in пары {
            for (старый, кандидат) in [
                (true, пара.исходный), (false, пара.целевой)
            ] {
                guard ключ(путь) == ключ(кандидат) else { continue }
                try требоватьСсылки(
                    точно(путь, кандидат), "регистр-или-NFC-ссылки"
                )
                совпадения += 1
                if старый { назначение = пара.целевой }
            }
        }
        try требоватьСсылки(совпадения <= 1, "неоднозначная-пара")
        guard let назначение else { return nil }

        let родитель = документ.split(separator: "/").dropLast().map(String.init)
        let цель = назначение.split(separator: "/").map(String.init)
        var общий = 0
        while общий < родитель.count && общий < цель.count
            && точно(родитель[общий], цель[общий]) {
            общий += 1
        }
        let части = Array(repeating: "..", count: родитель.count - общий)
            + Array(цель.dropFirst(общий))
        return закодировать(части.joined(separator: "/"), угловое: угловое)
            + адрес.суффикс
    }
}


private final class БюджетПеречняАдресов {
    let пределы: ПределыПеречняАдресов
    var осталось: Int
    var исчерпан = false
    var числоУзлов = 0, числоОшибок = 0, числоДиапазонов = 0, числоСвязей = 0
    init(_ пределы: ПределыПеречняАдресов) { self.пределы = пределы; осталось = пределы.шаги }
    func потратить(_ число: Int = 1) -> Bool {
        guard !исчерпан, число >= 0, число <= осталось else { исчерпан = true; return false }
        осталось -= число; return true
    }
    func учесть(_ число: Int = 1, текущий: inout Int, предел: Int) -> Bool {
        guard !исчерпан, число >= 0, число <= предел - текущий else { исчерпан = true; return false }
        текущий += число; return true
    }
}

private final class СканерСсылокПакета {
    enum РежимМасок { case общие, однофайловые }

    struct Строка {
        let начало: Int
        let телоКонец: Int
        let конец: Int
    }

    let байты: [UInt8]
    let путь: String
    let строки: [Строка]
    var скрыто: [Bool]
    var защищено: [Bool]
    var занято: [Bool]
    var неподдержано: [Bool]
    let бюджет: БюджетПеречняАдресов?
    let наблюдение: НаблюдениеОднофайловогоПлана?

    init(_ документ: ДокументСсылокПакета, строгий: Bool = false, бюджет: БюджетПеречняАдресов? = nil,
         наблюдение: НаблюдениеОднофайловогоПлана? = nil, маски: РежимМасок = .общие) throws {
        self.бюджет = бюджет
        self.наблюдение = наблюдение
        try требоватьСсылки(бюджет?.потратить(документ.байты.count) != false, "предел-диагностического-обхода")
        try требоватьСсылки(
            String(data: документ.байты, encoding: .utf8) != nil,
            "не-UTF8-Markdown"
        )
        путь = документ.путь
        байты = Array(документ.байты)
        скрыто = Array(repeating: false, count: байты.count)
        защищено = скрыто
        занято = скрыто
        неподдержано = скрыто
        var список: [Строка] = []
        var начало = 0
        for номер in байты.indices where байты[номер] == 10 {
            let конецТела = номер > начало && байты[номер - 1] == 13
                ? номер - 1 : номер
            список.append(.init(
                начало: начало, телоКонец: конецТела, конец: номер + 1
            ))
            начало = номер + 1
        }
        if начало < байты.count || список.isEmpty {
            список.append(.init(
                начало: начало, телоКонец: байты.count, конец: байты.count
            ))
        }
        строки = список
        switch маски {
        case .общие:
            наблюдение?.установитьУчасток("общие-маски")
            try построитьМаски(строгий: строгий)
        case .однофайловые:
            try маскиОдногоФайла()
        }
        try проверитьБюджет()
    }

    func потратить(_ число: Int = 1) -> Bool {
        let наблюдениеДопускает = наблюдение?.учесть(.работа, число) ?? true
        let бюджетДопускает = бюджет?.потратить(число) ?? true
        return наблюдениеДопускает && бюджетДопускает
    }
    func проверитьБюджет() throws {
        try наблюдение?.проверить()
        try требоватьСсылки(бюджет?.исчерпан != true, "предел-диагностического-обхода")
    }
    func текст(_ диапазон: Range<Int>) -> String {
        guard наблюдение?.учесть(.байтыДекодирования, диапазон.count, курсор: диапазон.lowerBound) != false else { return "" }
        guard потратить(диапазон.count) else { return "" }
        return String(decoding: байты[диапазон], as: UTF8.self)
    }

    func отметить(_ диапазон: Range<Int>, _ маска: inout [Bool]) {
        guard потратить(диапазон.count) else { return }
        for номер in диапазон { маска[номер] = true }
    }

    func экранирован(_ номер: Int) -> Bool {
        var курсор = номер
        var число = 0
        while курсор > 0 && байты[курсор - 1] == 92 {
            guard наблюдение?.учесть(.проверкиЭкранирования, курсор: курсор - 1) != false else { return false }
            guard потратить() else { return false }
            курсор -= 1
            число += 1
        }
        return число % 2 == 1
    }

    func видно(_ диапазон: Range<Int>) -> Bool {
        потратить(диапазон.count) && !диапазон.contains { скрыто[$0] }
    }

    func совпало(_ номер: Int, _ значение: String) -> Bool {
        let образец = Array(значение.utf8)
        return потратить(образец.count) && номер + образец.count <= байты.count
            && байты[номер..<(номер + образец.count)].elementsEqual(образец)
    }

    func пропуститьПробелы(_ начало: Int, перенос: Bool) -> Int {
        var курсор = начало
        while курсор < байты.count && [9, 32].contains(байты[курсор]) {
            guard потратить() else { return курсор }
            курсор += 1
        }
        if перенос && курсор < байты.count {
            if байты[курсор] == 13 {
                курсор += 1
                if курсор < байты.count && байты[курсор] == 10 { курсор += 1 }
            } else if байты[курсор] == 10 {
                курсор += 1
            } else {
                return курсор
            }
            while курсор < байты.count && [9, 32].contains(байты[курсор]) {
                guard потратить() else { return курсор }
                курсор += 1
            }
        }
        return курсор
    }

    func конецСтроки(_ начало: Int) -> (тело: Int, следующий: Int) {
        var номер = начало
        while номер < байты.count && байты[номер] != 10 {
            guard потратить() else { break }; номер += 1
        }
        let тело = номер > начало && байты[номер - 1] == 13 ? номер - 1 : номер
        return (тело, номер < байты.count ? номер + 1 : номер)
    }

    func закрытьМетку(_ начало: Int) -> Int? {
        var глубина = 1
        var курсор = начало + 1
        while курсор < байты.count {
            guard наблюдение?.учесть(.шагиПоиска, курсор: курсор) != false else { return nil }
            guard потратить() else { return nil }
            if скрыто[курсор] || [10, 13].contains(байты[курсор]) { return nil }
            if байты[курсор] == 92 && курсор + 1 < байты.count {
                курсор += 2
                continue
            }
            if байты[курсор] == 91 { глубина += 1 }
            if байты[курсор] == 93 {
                глубина -= 1
                if глубина == 0 { return курсор }
            }
            курсор += 1
        }
        return nil
    }

    func заголовок(_ начало: Int) -> Int? {
        guard начало < байты.count,
              [34, 39, 40].contains(байты[начало]) else { return nil }
        let открытие = байты[начало]
        let закрытие: UInt8 = открытие == 40 ? 41 : открытие
        var глубина = 1
        var курсор = начало + 1
        while курсор < байты.count {
            guard потратить() else { return nil }
            // Многострочный title здесь намеренно не принимается.
            if [10, 13].contains(байты[курсор]) { return nil }
            if байты[курсор] == 92 && курсор + 1 < байты.count {
                курсор += 2
                continue
            }
            if открытие == 40 && байты[курсор] == 40 { глубина += 1 }
            if байты[курсор] == закрытие {
                глубина -= 1
                if глубина == 0 { return курсор + 1 }
            }
            курсор += 1
        }
        return nil
    }

    func адрес(
        _ начало: Int, встроенный: Bool
    ) -> (диапазон: Range<Int>, угловое: Bool, конец: Int)? {
        guard начало < байты.count else { return nil }
        let угловое = байты[начало] == 60
        let началоАдреса = начало + (угловое ? 1 : 0)
        var курсор = началоАдреса
        var глубина = 0

        while курсор < байты.count {
            guard потратить() else { return nil }
            let знак = байты[курсор]
            if знак == 92 && курсор + 1 < байты.count {
                курсор += 2
                continue
            }
            if угловое {
                if знак == 62 {
                    return (началоАдреса..<курсор, true, курсор + 1)
                }
                if [10, 13, 60].contains(знак) { return nil }
            } else {
                if [9, 10, 13, 32].contains(знак) {
                    return глубина == 0
                        ? (началоАдреса..<курсор, false, курсор) : nil
                }
                if знак == 40 { глубина += 1 }
                if знак == 41 {
                    if глубина == 0 {
                        return встроенный
                            ? (началоАдреса..<курсор, false, курсор) : nil
                    }
                    глубина -= 1
                }
            }
            курсор += 1
        }
        return !угловое && глубина == 0
            ? (началоАдреса..<курсор, false, курсор) : nil
    }

    func встроенная(_ начало: Int, скобка: Int, допустимаСкрытаяПодпись: Bool = false) -> ТокенСсылкиПакета? {
        let началоАдреса = пропуститьПробелы(скобка + 1, перенос: true)
        guard let разбор = адрес(началоАдреса, встроенный: true) else {
            return nil
        }
        var курсор = разбор.конец
        let разделитель = курсор
        курсор = пропуститьПробелы(курсор, перенос: true)
        if курсор < байты.count && байты[курсор] != 41 {
            guard курсор > разделитель, let конец = заголовок(курсор) else {
                return nil
            }
            курсор = пропуститьПробелы(конец, перенос: true)
        }
        guard курсор < байты.count, байты[курсор] == 41,
              видно((допустимаСкрытаяПодпись ? скобка : начало)..<(курсор + 1)) else { return nil }
        return .init(
            целиком: начало..<(курсор + 1),
            адрес: разбор.диапазон,
            угловое: разбор.угловое,
            меткаОпределения: nil,
            метка: (начало + (байты[начало] == 33 ? 2 : 1))..<(скобка - 1)
        )
    }

    // Только однофайловый вход: прежний строгий разбор вызывается первым.
    // Исторический адрес без title сохраняет точный диапазон исходных байтов;
    // существование и однозначность локальной цели проверяет вызывающая сторона.
    func встроеннаяСИсторическимиПробелами(
        _ начало: Int, скобка: Int, допустимаСкрытаяПодпись: Bool
    ) -> ТокенСсылкиПакета? {
        let началоАдреса = скобка + 1
        guard началоАдреса < байты.count else { return nil }
        var курсор = началоАдреса, естьПробел = false
        while курсор < байты.count && байты[курсор] != 41 {
            guard потратить() else { return nil }
            let знак = байты[курсор]
            if знак == 32 { естьПробел = true }
            else if знак < 33 || знак == 127 || [34, 39, 40, 60, 62, 91, 92, 93].contains(знак) { return nil }
            курсор += 1
        }
        guard естьПробел, курсор > началоАдреса, курсор < байты.count,
              байты[началоАдреса] != 32, байты[курсор - 1] != 32,
              видно((допустимаСкрытаяПодпись ? скобка : начало)..<(курсор + 1)) else { return nil }
        return .init(
            целиком: начало..<(курсор + 1),
            адрес: началоАдреса..<курсор,
            угловое: false,
            меткаОпределения: nil,
            метка: (начало + (байты[начало] == 33 ? 2 : 1))..<(скобка - 1)
        )
    }

    func ключМетки(_ значение: String) -> String {
        АдресСсылкиПакета.ключ(
            АдресСсылкиПакета.снятьЭкранирование(значение)
                .split(whereSeparator: \.isWhitespace)
                .joined(separator: " ")
        )
    }

    func определение(_ строка: Строка) -> ТокенСсылкиПакета? {
        var начало = строка.начало
        var отступ = 0
        while начало < строка.телоКонец && байты[начало] == 32 && отступ < 3 {
            начало += 1
            отступ += 1
        }
        guard начало < строка.телоКонец, байты[начало] == 91,
              let закрытие = закрытьМетку(начало),
              закрытие + 1 < строка.телоКонец,
              байты[закрытие + 1] == 58 else { return nil }

        let началоАдреса = пропуститьПробелы(закрытие + 2, перенос: true)
        guard let разбор = адрес(началоАдреса, встроенный: false),
              !разбор.диапазон.isEmpty else { return nil }
        var курсор = пропуститьПробелы(разбор.конец, перенос: false)
        var предел = конецСтроки(курсор)

        if курсор == предел.тело && предел.следующий < байты.count {
            let следующий = пропуститьПробелы(предел.следующий, перенос: false)
            if следующий < байты.count && [34, 39, 40].contains(байты[следующий]) {
                курсор = следующий
                предел = конецСтроки(курсор)
            }
        }
        if курсор < предел.тело {
            guard let конец = заголовок(курсор) else { return nil }
            курсор = пропуститьПробелы(конец, перенос: false)
        }
        guard курсор == предел.тело,
              видно(начало..<курсор) else { return nil }
        return .init(
            целиком: начало..<предел.следующий,
            адрес: разбор.диапазон,
            угловое: разбор.угловое,
            меткаОпределения: ключМетки(текст((начало + 1)..<закрытие)),
            метка: (начало + 1)..<закрытие
        )
    }

    func построитьМаски(строгий: Bool = false) throws {
        var комментарий = false
        var ограда: (знак: UInt8, длина: Int)?
        var передняяЧасть = false

        if let первая = строки.first, текст(первая.начало..<первая.телоКонец) == "+++" {
            передняяЧасть = true
        }

        for (номерСтроки, строка) in строки.enumerated() {
            try требоватьСсылки(потратить(), "предел-диагностического-обхода")
            let весь = строка.начало..<строка.конец
            let тело = текст(строка.начало..<строка.телоКонец)
            if передняяЧасть {
                отметить(весь, &скрыто)
                if номерСтроки > 0 && тело == "+++" { передняяЧасть = false }
                continue
            }

            var начало = строка.начало
            while начало < строка.телоКонец
                && байты[начало] == 32
                && начало - строка.начало < 3 {
                начало += 1
            }

            if let текущая = ограда {
                отметить(весь, &скрыто)
                var конец = начало
                while конец < строка.телоКонец
                    && байты[конец] == текущая.знак && потратить() { конец += 1 }
                if конец - начало >= текущая.длина,
                   потратить(строка.телоКонец - конец),
                   байты[конец..<строка.телоКонец].allSatisfy({
                       $0 == 9 || $0 == 32
                   }) {
                    ограда = nil
                }
                continue
            }

            // Не угадываем вложенность list/blockquote continuation.
            let неподдержанныйКонтейнер = строгий
                ? (ИменаПутей.имеетПрефикс(тело, "    ") || ИменаПутей.имеетПрефикс(тело, "\t")
                    || ИменаПутей.имеетПрефикс(тело.trimmingCharacters(in: .whitespaces), ">"))
                : (тело.hasPrefix("    ") || тело.hasPrefix("\t") || тело.trimmingCharacters(in: .whitespaces).hasPrefix(">"))
            if неподдержанныйКонтейнер {
                отметить(весь, &неподдержано)
            }

            if !комментарий, начало < строка.телоКонец, !скрыто[начало],
               [96, 126].contains(байты[начало]) {
                var конец = начало
                while конец < строка.телоКонец
                    && байты[конец] == байты[начало] && потратить() { конец += 1 }
                if конец - начало >= 3 && (байты[начало] != 96 || (потратить(строка.телоКонец - конец) && !байты[конец..<строка.телоКонец].contains(96))) {
                    ограда = (байты[начало], конец - начало)
                    отметить(весь, &скрыто)
                    continue
                }
            }

            var курсор = строка.начало
            while курсор < строка.телоКонец {
                try требоватьСсылки(потратить(), "предел-диагностического-обхода")
                if скрыто[курсор] { курсор += 1; continue }
                if комментарий {
                    скрыто[курсор] = true
                    if совпало(курсор, "-->") {
                        отметить(курсор..<(курсор + 3), &скрыто)
                        курсор += 3
                        комментарий = false
                    } else {
                        курсор += 1
                    }
                    continue
                }
                if совпало(курсор, "<!--") {
                    отметить(курсор..<(курсор + 4), &скрыто)
                    курсор += 4
                    комментарий = true
                    continue
                }
                if байты[курсор] == 96 && !экранирован(курсор) {
                    var конецОткрытия = курсор
                    while конецОткрытия < строка.телоКонец
                        && байты[конецОткрытия] == 96 && потратить() { конецОткрытия += 1 }
                    let длина = конецОткрытия - курсор
                    var предел = байты.count
                    for следующая in строки {
                        try требоватьСсылки(наблюдение?.учесть(.строкиОбщихМасок, курсор: следующая.начало) != false, "предел-наблюдения-общих-масок")
                        try требоватьСсылки(потратить(), "предел-диагностического-обхода")
                        guard следующая.начало >= строка.конец else { continue }
                        let телоСледующей = текст(следующая.начало..<следующая.телоКонец)
                        if телоСледующей.trimmingCharacters(in: .whitespaces).isEmpty
                            || телоСледующей.range(of: #"^[ ]{0,3}(?:#{1,6}(?:[ \t]|$)|>|[-+*][ \t]|[0-9]{1,9}[.)][ \t]|`{3}|~{3}|(?:=+|-+)[ \t]*$)"#, options: .regularExpression) != nil {
                            предел = следующая.начало; break
                        }
                    }
                    var поиск = конецОткрытия
                    var закрытие: Int?
                    while поиск < предел {
                        try требоватьСсылки(наблюдение?.учесть(.шагиПоиска, курсор: поиск) != false, "предел-наблюдения-поиска")
                        try требоватьСсылки(потратить(), "предел-диагностического-обхода")
                        if байты[поиск] != 96 { поиск += 1; continue }
                        var конец = поиск
                        while конец < предел && байты[конец] == 96 {
                            try требоватьСсылки(потратить(), "предел-диагностического-обхода")
                            конец += 1
                        }
                        if конец - поиск == длина { закрытие = конец; break }
                        поиск = конец
                    }
                    guard let закрытие else {
                        отметить(весь, &неподдержано)
                        курсор = конецОткрытия
                        continue
                    }
                    отметить(курсор..<закрытие, &скрыто)
                    курсор = закрытие
                    continue
                }
                курсор += 1
            }
        }
        try проверитьБюджет()
        try требоватьСсылки(!передняяЧасть, "незамкнутая-передняя-часть")
        if строгий {
            try требоватьСсылки(ограда == nil && !комментарий, "незамкнутая-ограда-или-комментарий")
        }

        if (строгий ? ИменаПутей.имеетПрефикс(путь, "Источники/") : путь.hasPrefix("Источники/")) {
            защищено = Array(repeating: true, count: байты.count)
            return
        }

        var разделы: [(строка: Строка, название: String)] = []
        for строка in строки {
            try требоватьСсылки(потратить(), "предел-диагностического-обхода")
            let диапазон = строка.начало..<строка.телоКонец
            guard видно(диапазон) else { continue }
            let видимое = текст(диапазон)
            guard видимое.range(
                of: #"^[ ]{0,3}##[ \t]+"#,
                options: .regularExpression
            ) != nil else { continue }
            let название = видимое
                .replacingOccurrences(
                    of: #"^[ ]{0,3}##[ \t]+"#,
                    with: "", options: .regularExpression
                )
                .replacingOccurrences(
                    of: #"[ \t]+#+[ \t]*$"#,
                    with: "", options: .regularExpression
                )
                .trimmingCharacters(in: .whitespaces)
            разделы.append((строка, название))
        }
        let запрос = (строгий ? ИменаПутей.имеетПрефикс(путь, "Журнал/") : путь.hasPrefix("Журнал/"))
            && (путь as NSString).lastPathComponent == "запрос.md"
        let число = разделы.filter { $0.название == "Текст запроса" }.count
        if запрос && число != 1 {
            // Не классифицируем неизвестную старую форму как производную.
            защищено = Array(repeating: true, count: байты.count)
            return
        }
        for номер in разделы.indices
            where разделы[номер].название == "Текст запроса" {
            let конец = номер + 1 < разделы.count
                ? разделы[номер + 1].строка.начало : байты.count
            отметить(разделы[номер].строка.конец..<конец, &защищено)
        }
    }
}

// Чистый префикс только однофайлового контракта. Диапазон — UTF-8 тело строки;
// Переданные функции сохраняют существующие учёт работы и декодирование сканера.
enum ПрефиксКонтейнераОдногоФайла {
    static func начало(_ байты: [UInt8], диапазон: Range<Int>,
        потратить: (Int) -> Bool, текст: (Range<Int>) -> String) -> Int {
        func границаЮникода(_ кандидат: Int, от начало: Int) -> Int? {
            guard кандидат < диапазон.upperBound && байты[кандидат] >= 128 else { return nil }
            // String.range отвергает конец совпадения внутри графемы.
            // После первого не-ASCII байта контейнер продолжиться не может:
            // старый oracle нужен один раз, после него сразу возвращаемся.
            let остаток = текст(начало..<диапазон.upperBound)
            guard let совпадение = остаток.range(of: #"^[ ]{0,3}(?:>[ \t]?|(?:[-+*]|[0-9]{1,9}[.)])(?:[ \t]+|$))"#, options: .regularExpression) else { return начало }
            return начало + остаток[совпадение].utf8.count
        }
        var курсор = диапазон.lowerBound
        while курсор < диапазон.upperBound {
            guard потратить(1) else { return курсор }
            var кандидат = курсор, отступ = 0
            while кандидат < диапазон.upperBound && байты[кандидат] == 32 && отступ < 3 {
                guard потратить(1) else { return курсор }
                кандидат += 1; отступ += 1
            }
            guard кандидат < диапазон.upperBound else { return курсор }
            if байты[кандидат] == 62 {
                кандидат += 1
                if кандидат < диапазон.upperBound && [9, 32].contains(байты[кандидат]) {
                    guard потратить(1) else { return курсор }
                    кандидат += 1
                }
                if let граница = границаЮникода(кандидат, от: курсор) { return граница }
                курсор = кандидат; continue
            }
            if [42, 43, 45].contains(байты[кандидат]) { кандидат += 1 }
            else {
                var цифр = 0
                while кандидат < диапазон.upperBound && (48...57).contains(байты[кандидат]) && цифр < 9 {
                    guard потратить(1) else { return курсор }
                    кандидат += 1; цифр += 1
                }
                guard цифр > 0 && кандидат < диапазон.upperBound && [41, 46].contains(байты[кандидат]) else { return курсор }
                кандидат += 1
            }
            if кандидат == диапазон.upperBound { return кандидат }
            if [9, 32].contains(байты[кандидат]) {
                repeat {
                    guard потратить(1) else { return курсор }
                    кандидат += 1
                } while кандидат < диапазон.upperBound && [9, 32].contains(байты[кандидат])
                if let граница = границаЮникода(кандидат, от: курсор) { return граница }
                курсор = кандидат; continue
            }
            // ICU $ допускает некоторые конечные разделители строки.
            // Проверяется один завершающий суффикс, а не каждый префикс.
            let остаток = текст(кандидат..<диапазон.upperBound)
            return остаток.range(of: #"^$"#, options: .regularExpression) != nil ? кандидат : курсор
        }
        return курсор
    }
}

// Только маски canonical one-file контракта. Общие/fixed9 входы сохраняют
// прежние маски и отказы; лексер и UTF8 диапазоны используются совместно.
private extension СканерСсылокПакета {
    func началоКонтейнера(_ строка: Строка) -> Int {
        guard наблюдение?.учесть(.контейнеры, курсор: строка.начало) != false else { return строка.начало }
        return ПрефиксКонтейнераОдногоФайла.начало(байты, диапазон: строка.начало..<строка.телоКонец,
            потратить: { self.потратить($0) }, текст: { self.текст($0) })
    }
    func маскиОдногоФайла() throws {
        наблюдение?.установитьУчасток("однофайловые-маски")
        скрыто = Array(repeating: false, count: байты.count)
        защищено = скрыто; занято = скрыто
        var передняяЧасть = строки.first.map { текст($0.начало..<$0.телоКонец) == "+++" } ?? false
        var комментарий = false, ограда: (UInt8, Int)?
        for (номер, строка) in строки.enumerated() {
            let весь = строка.начало..<строка.конец
            if передняяЧасть {
                отметить(весь, &скрыто)
                if номер > 0 && текст(строка.начало..<строка.телоКонец) == "+++" { передняяЧасть = false }
                continue
            }
            let начало = началоКонтейнера(строка), тело = текст(начало..<строка.телоКонец)
            if let текущая = ограда {
                отметить(весь, &скрыто)
                let знак = текущая.0 == 96 ? "`" : "~"
                if тело.range(of: "^[ ]{0,3}" + знак + "{" + String(текущая.1) + ",}[ \\t]*$", options: .regularExpression) != nil { ограда = nil }
                continue
            }
            if !комментарий && (тело.hasPrefix("    ") || тело.hasPrefix("\t")) { отметить(весь, &скрыто); continue }
            var курсор = строка.начало
            while курсор < строка.телоКонец {
                if комментарий {
                    if совпало(курсор, "-->") { отметить(курсор..<(курсор + 3), &скрыто); курсор += 3; комментарий = false }
                    else { скрыто[курсор] = true; курсор += 1 }
                } else if совпало(курсор, "<!--") { отметить(курсор..<(курсор + 4), &скрыто); курсор += 4; комментарий = true }
                else { курсор += 1 }
            }
            var видимые = байты[строка.начало..<строка.телоКонец].enumerated().map { скрыто[строка.начало + $0.offset] ? UInt8(32) : $0.element }
            // Префикс контейнера уже вычислен по исходным байтам; маска комментариев
            // не открывает ссылку или ограду внутри скрытого текста.
            let смещение = начало - строка.начало
            видимые.removeFirst(min(смещение, видимые.count))
            let видимое = String(decoding: видимые, as: UTF8.self)
            if let диапазон = видимое.range(of: #"^[ ]{0,3}(`{3,}|~{3,})"#, options: .regularExpression) {
                let маркер = видимое[диапазон].trimmingCharacters(in: .whitespaces)
                ограда = (маркер.utf8.first!, маркер.utf8.count); отметить(весь, &скрыто)
            }
        }
        try требоватьСсылки(!передняяЧасть, "незамкнутая-передняя-часть")
        var курсор = 0
        while курсор < байты.count {
            try требоватьСсылки(наблюдение?.учесть(.шагиПоиска, курсор: курсор) != false, "предел-наблюдения-масок")
            if скрыто[курсор] || байты[курсор] != 96 { курсор += 1; continue }
            var конец = курсор
            while конец < байты.count && !скрыто[конец] && байты[конец] == 96 { конец += 1 }
            let длина = конец - курсор
            var поиск = конец, закрытие: Int?
            while поиск < байты.count {
                try требоватьСсылки(наблюдение?.учесть(.шагиПоиска, курсор: поиск) != false, "предел-наблюдения-масок")
                if скрыто[поиск] || байты[поиск] != 96 { поиск += 1; continue }
                var правый = поиск
                while правый < байты.count && !скрыто[правый] && байты[правый] == 96 { правый += 1 }
                if правый - поиск == длина { закрытие = правый; break }; поиск = правый
            }
            if let закрытие { отметить(курсор..<закрытие, &скрыто); курсор = закрытие } else { курсор = конец }
        }
        if ИменаПутей.имеетПрефикс(путь, "Источники/") { защищено = Array(repeating: true, count: байты.count); return }
        guard путь.range(of: #"^Журнал/[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}-[0-9]{2}-[0-9]{2}_MSK(?:_[^/]+)?/запрос\.md$"#, options: .regularExpression) != nil else { return }
        var разделы: [(Строка, String)] = []
        for строка in строки {
            let видимое = String(decoding: байты[строка.начало..<строка.телоКонец].enumerated().map { скрыто[строка.начало + $0.offset] ? UInt8(32) : $0.element }, as: UTF8.self)
            if видимое.range(of: #"^[ ]{0,3}##(?!#)[ \t]+"#, options: .regularExpression) != nil {
                let название = видимое.replacingOccurrences(of: #"^[ ]{0,3}##[ \t]+|[ \t]+#+[ \t]*$"#, with: "", options: .regularExpression).trimmingCharacters(in: .whitespaces)
                разделы.append((строка, название))
            }
        }
        let выбранные = разделы.indices.filter { разделы[$0].1 == "Текст запроса" }
        try требоватьСсылки(выбранные.count == 1, "нужен-единственный-раздел-текста-запроса")
        let номер = выбранные[0], конец = номер + 1 < разделы.count ? разделы[номер + 1].0.начало : байты.count
        отметить(разделы[номер].0.конец..<конец, &защищено)
    }
}

struct РазборСсылокОдногоФайла: Sendable {
    let правки: [ПравкаФайлаПереименования]
    // Эти обязательства проверяет IO, включая отсутствующие/ignored префиксы.
    let локальныеЦели: [String]
}

enum СсылкиОдногоФайла {
    // Чистая операция: конечный явный namespace и документы, без IO/Git.
    static func переписать(документы: [ДокументСсылокПакета], исходный: String, целевой: String,
        пути: [String], алиасы: [String: String] = [:],
        пределФайла: Int = 8_388_608, пределБайтов: Int = 268_435_456,
        наблюдение: НаблюдениеОднофайловогоПлана? = nil) throws -> РазборСсылокОдногоФайла {
        let входныеБайты = документы.reduce(0) { $0 + $1.байты.count }
        try требоватьСсылки(пределФайла >= 0 && пределБайтов >= 0 && входныеБайты <= пределБайтов
            && документы.allSatisfy { $0.байты.count <= пределФайла }, "предел-one-file-документов")
        var свободныеБайты = пределБайтов - входныеБайты
        let упорядоченные = документы.sorted(by: { порядокПутей($0.путь, $1.путь) })
        try наблюдение?.этап(.разбор, путь: упорядоченные.first?.путь, номер: 1, всего: документы.count,
            хэш: упорядоченные.first?.sha256, байты: упорядоченные.first?.байты.count)
        let пространство = Set(пути.map { Data($0.utf8) })
        let поКлючу = autoreleasepool { Dictionary(grouping: пути, by: АдресСсылкиПакета.ключ) }
        try требоватьСсылки(Set(документы.map { Data($0.путь.utf8) }).count == документы.count, "повторный-документ-one-file")
        func соответствуетИсточнику(_ путь: String) -> Bool { АдресСсылкиПакета.ключ(путь) == АдресСсылкиПакета.ключ(исходный) }
        func черезАлиас(_ путь: String) -> String? {
            for (алиас, цель) in алиасы.sorted(by: { $0.key.utf8.count > $1.key.utf8.count }) {
                if АдресСсылкиПакета.точно(путь, алиас) { return цель }
                if ИменаПутей.имеетПрефикс(путь, алиас + "/") { return цель + String(путь.dropFirst(алиас.count)) }
            }
            return nil
        }
        func проверитьЦель(_ путь: String) throws {
            try требоватьСсылки(пространство.contains(Data(путь.utf8)) && (поКлючу[АдресСсылкиПакета.ключ(путь)]?.count ?? 0) == 1 && черезАлиас(путь) == nil,
                "сломанная-исходящая-или-case-NFC-symlink-цель")
            try требоватьСсылки(!ПереименованиеФайла.исключён(путь), "исходящая-цель-в-исключённой-области")
        }
        func значимаяВики(_ значение: String, документ: String) -> Bool {
            let сырое = String(значение.split(separator: "|", omittingEmptySubsequences: false)[0]).split(separator: "#", omittingEmptySubsequences: false)[0].trimmingCharacters(in: .whitespaces)
            guard !сырое.isEmpty else { return false }
            let снято = АдресСсылкиПакета.снятьЭкранирование(сырое)
            let варианты = [снято, (try? АдресСсылкиПакета.декодировать(снято, побайтово: true)) ?? снято]
            for вариант in варианты {
                if !вариант.contains("/") {
                    let имена = [(исходный as NSString).lastPathComponent, ((исходный as NSString).lastPathComponent as NSString).deletingPathExtension]
                    if имена.contains(where: { АдресСсылкиПакета.ключ($0) == АдресСсылкиПакета.ключ(вариант) }) { return true }
                }
                for имя in [вариант, (вариант as NSString).pathExtension.isEmpty ? вариант + ".md" : вариант] {
                    for контекст in [документ, "корневой-документ.md"] {
                        if let адрес = try? АдресСсылкиПакета.разобрать(имя, документ: контекст, побайтово: true), let путь = адрес.путь, соответствуетИсточнику(путь) { return true }
                    }
                }
            }
            return false
        }
        var результаты: [ПравкаФайлаПереименования] = [], локальныеЦели: [Data: String] = [:]
        for (номерДокумента, документ) in упорядоченные.enumerated() {
            do {
            try autoreleasepool {
            try требоватьСсылки(хэшПутей(документ.байты) == документ.sha256 && !документ.байты.contains(0), "дрейф-или-NUL-Markdown")
            наблюдение?.установитьДокумент(номер: номерДокумента + 1, всего: документы.count,
                путь: документ.путь, хэш: документ.sha256, байты: документ.байты.count)
            try наблюдение?.проверить()
            let сканер = try СканерСсылокПакета(документ, наблюдение: наблюдение, маски: .однофайловые)
            try наблюдение?.проверить()
            let перемещаемый = АдресСсылкиПакета.точно(документ.путь, исходный)
            let будущийДокумент = перемещаемый ? целевой : документ.путь
            var токены: [ТокенСсылкиПакета] = [], определения: Set<String> = [], защищённыеМетки: Set<String> = []
            наблюдение?.установитьУчасток("определения")
            for строка in сканер.строки {
                let начало = сканер.началоКонтейнера(строка)
                let видимая = СканерСсылокПакета.Строка(начало: начало, телоКонец: строка.телоКонец, конец: строка.конец)
                if let токен = сканер.определение(видимая), let метка = токен.меткаОпределения {
                    try требоватьСсылки(определения.insert(метка).inserted, "повторная-reference-метка")
                    токены.append(токен); сканер.отметить(токен.целиком, &сканер.занято)
                } else {
                    var префикс = начало, отступ = 0
                    while префикс < строка.телоКонец && сканер.байты[префикс] == 32 && отступ < 3 {
                        префикс += 1; отступ += 1
                    }
                    if префикс < строка.телоКонец, сканер.байты[префикс] == 91,
                       !сканер.экранирован(префикс), let закрытие = сканер.закрытьМетку(префикс),
                       закрытие + 1 < строка.телоКонец, сканер.байты[закрытие + 1] == 58,
                       сканер.видно(префикс..<(закрытие + 2)) {
                        throw ОтказСсылокПакета.условие("one-file-неподдержанное-reference-определение")
                    }
                }
            }
            func закрытиеПодписи(_ начало: Int) throws -> Int? {
                if let конец = сканер.закрытьМетку(начало) { return конец }
                var курсор = начало + 1, глубина = 1, естьСкрытое = false
                while курсор < сканер.байты.count && ![10, 13].contains(сканер.байты[курсор]) {
                    try требоватьСсылки(наблюдение?.учесть(.шагиПоиска, курсор: курсор) != false, "предел-наблюдения-подписи")
                    if сканер.скрыто[курсор] { естьСкрытое = true; курсор += 1; continue }
                    if сканер.экранирован(курсор) { курсор += 1; continue }
                    if сканер.байты[курсор] == 91 { глубина += 1 }
                    if сканер.байты[курсор] == 93 {
                        глубина -= 1
                        if глубина == 0 {
                            if естьСкрытое && курсор + 1 < сканер.байты.count {
                                if сканер.байты[курсор + 1] == 40 { return курсор }
                                if сканер.байты[курсор + 1] == 58 { throw ОтказСсылокПакета.условие("one-file-код-в-подписи") }
                            }
                            return nil
                        }
                    }
                    курсор += 1
                }
                return nil
            }
            var курсор = 0
            наблюдение?.установитьУчасток("токены")
            while курсор < сканер.байты.count {
                try требоватьСсылки(наблюдение?.учесть(.шагиПоиска, курсор: курсор) != false, "предел-наблюдения-токенов")
                if сканер.скрыто[курсор] || сканер.занято[курсор] { курсор += 1; continue }
                if сканер.совпало(курсор, "[[") && !сканер.экранирован(курсор) {
                    var конец = курсор + 2
                    while конец < сканер.байты.count && ![10, 13].contains(сканер.байты[конец]) && !сканер.совпало(конец, "]]") { конец += 1 }
                    if сканер.совпало(конец, "]]") {
                        try требоватьСсылки(!значимаяВики(сканер.текст((курсор + 2)..<конец), документ: документ.путь), "wiki-ссылка-на-переносимый-файл")
                        курсор = конец + 2; continue
                    }
                }
                let открытие = сканер.байты[курсор] == 33 && курсор + 1 < сканер.байты.count && сканер.байты[курсор + 1] == 91 ? курсор + 1 : курсор
                if сканер.байты[открытие] == 91, !сканер.экранирован(открытие), let закрытие = try закрытиеПодписи(открытие) {
                    let вложенная = ((открытие + 1)..<закрытие).contains { !сканер.скрыто[$0] && [91, 60].contains(сканер.байты[$0]) && !сканер.экранирован($0) }
                    if закрытие + 1 < сканер.байты.count && [40, 91].contains(сканер.байты[закрытие + 1]) {
                        try требоватьСсылки(!вложенная, "one-file-вложенная-подпись")
                    }
                    if закрытие + 1 < сканер.байты.count && сканер.байты[закрытие + 1] == 40 {
                        let скрытаяПодпись = ((открытие + 1)..<закрытие).contains { сканер.скрыто[$0] }
                        let строгий = сканер.встроенная(курсор, скобка: закрытие + 1, допустимаСкрытаяПодпись: скрытаяПодпись)
                        guard let токен = строгий ?? сканер.встроеннаяСИсторическимиПробелами(
                            курсор, скобка: закрытие + 1, допустимаСкрытаяПодпись: скрытаяПодпись
                        ) else { throw ОтказСсылокПакета.условие("неполная-встроенная-ссылка") }
                        if case nil = строгий {
                            let сырое = сканер.текст(токен.адрес)
                            let (сыройПуть, суффикс) = АдресСсылкиПакета.разделить(сырое)
                            try требоватьСсылки(сыройПуть.utf8.contains(32) && !суффикс.utf8.contains(32), "неполная-встроенная-ссылка")
                            let адрес = try АдресСсылкиПакета.разобрать(сырое, документ: документ.путь, побайтово: true)
                            guard let цель = адрес.путь else { throw ОтказСсылокПакета.условие("one-file-исторический-адрес-не-локальный") }
                            try проверитьЦель(цель)
                        }
                        if скрытаяПодпись {
                            let сырое = сканер.текст(токен.адрес)
                            let прежний = try АдресСсылкиПакета.разобрать(сырое, документ: документ.путь, побайтово: true)
                            if let цель = прежний.путь {
                                локальныеЦели[Data(цель.utf8)] = цель
                                if перемещаемый { try проверитьЦель(цель) }
                                let точная = АдресСсылкиПакета.точно(цель, исходный)
                                let будущаяЦель = точная ? целевой : цель
                                let будущий = try АдресСсылкиПакета.разобрать(сырое, документ: будущийДокумент, побайтово: true)
                                try требоватьСсылки((!соответствуетИсточнику(цель) || точная)
                                    && !(черезАлиас(цель).map(соответствуетИсточнику) ?? false)
                                    && будущий.путь.map { АдресСсылкиПакета.точно($0, будущаяЦель) } == true,
                                    "one-file-код-в-подписи")
                            }
                            // Все вложенные формы уже закрыты guard выше. Сохраняем
                            // только доказанно неизменяемый адрес; IO проверит префиксы.
                            курсор = токен.целиком.upperBound; continue
                        }
                        токены.append(токен); курсор = токен.целиком.upperBound; continue
                    }
                    var метка = сканер.ключМетки(сканер.текст((открытие + 1)..<закрытие)), конец = закрытие + 1
                    if конец < сканер.байты.count && сканер.байты[конец] == 91, let правый = сканер.закрытьМетку(конец) {
                        if правый > конец + 1 { метка = сканер.ключМетки(сканер.текст((конец + 1)..<правый)) }; конец = правый + 1
                    }
                    if определения.contains(метка) {
                        try требоватьСсылки(!вложенная, "one-file-вложенная-подпись")
                        if (курсор..<конец).contains(where: { сканер.защищено[$0] }) { защищённыеМетки.insert(метка) }
                        курсор = конец
                    } else { курсор = открытие + 1 }
                    continue
                }
                курсор += 1
            }
            var правки: [ПравкаСсылкиПакета] = []
            for токен in токены.sorted(by: { $0.адрес.lowerBound < $1.адрес.lowerBound }) {
                let сырое = сканер.текст(токен.адрес)
                let адрес = try АдресСсылкиПакета.разобрать(сырое, документ: документ.путь, побайтово: true)
                guard let цель = адрес.путь else { continue }
                локальныеЦели[Data(цель.utf8)] = цель
                let точнаяЦель = АдресСсылкиПакета.точно(цель, исходный)
                if !перемещаемый && !точнаяЦель {
                    try требоватьСсылки(!соответствуетИсточнику(цель) && !(черезАлиас(цель).map(соответствуетИсточнику) ?? false), "входящая-case-NFC-symlink-ссылка")
                    continue
                }
                if перемещаемый { try проверитьЦель(цель) }
                let пустойПуть = АдресСсылкиПакета.разделить(сырое).0.isEmpty
                let новаяЦель = точнаяЦель ? целевой : цель
                let новое = пустойПуть ? сырое : АдресСсылкиПакета.относительныйПуть(новаяЦель, документ: будущийДокумент, угловое: токен.угловое) + адрес.суффикс
                guard !АдресСсылкиПакета.точно(сырое, новое) else { continue }
                try требоватьСсылки(!токен.адрес.contains(where: { сканер.защищено[$0] }) && !(токен.меткаОпределения.map { защищённыеМетки.contains($0) } ?? false), "защищённая-живая-ссылка-блокирует-перенос")
                let обратно = try АдресСсылкиПакета.разобрать(новое, документ: будущийДокумент, побайтово: true)
                try требоватьСсылки(обратно.путь.map { АдресСсылкиПакета.точно($0, новаяЦель) } == true, "неверная-обратная-цель")
                правки.append(.init(диапазон: токен.адрес, прежние: документ.байты.subdata(in: токен.адрес), новые: Data(новое.utf8)))
            }
            let прибавка = правки.reduce(0) { $0 + $1.новые.count - $1.прежние.count }
            try требоватьСсылки(документ.байты.count + прибавка <= пределФайла && прибавка <= свободныеБайты, "предел-one-file-итоговых-байтов")
            свободныеБайты -= прибавка
            var будущие = документ.байты
            for номер in правки.indices where номер > 0 { try требоватьСсылки(правки[номер - 1].диапазон.upperBound <= правки[номер].диапазон.lowerBound, "пересекающиеся-one-file-правки") }
            for правка in правки.reversed() { будущие.replaceSubrange(правка.диапазон, with: правка.новые) }
            try сканер.проверитьБюджет()
            if будущие != документ.байты { результаты.append(.init(исходный: документ.путь, итоговый: будущийДокумент, байты: будущие, числоСсылок: правки.count)) }
            }
            } catch {
                try наблюдение?.проверить()
                throw ОтказСсылокПакета.условие("\(документ.путь): \(error)")
            }
        }
        return .init(правки: результаты.sorted { порядокПутей($0.итоговый, $1.итоговый) },
            локальныеЦели: локальныеЦели.values.sorted(by: порядокПутей))
    }
}

private struct ЧерновикУзлаАдресов {
    let вид: ВидУзлаПеречняАдресов
    let целиком: Range<Int>
    let адрес: Range<Int>?
    let подпись: Range<Int>?
    let метка: Range<Int>?
    let ключ: String?
    let изображение: Bool
}
private struct СобранныеСсылкиМиграции {
    let сканер: СканерСсылокПакета
    let токены: [ТокенСсылкиПакета]
    let защищённыеМетки: Set<String>
    let активныеМетки: Set<String>
    let узлы: [ЧерновикУзлаАдресов]
    let ошибки: [ОшибкаПеречняАдресов]
    let неизвестные: [Range<Int>]
}

// Общий сборщик только для general resolver и диагностического входа.
// nil-бюджет сохраняет прежние ранние отказы; batch9 сюда не подключён.
private func собратьСсылкиМиграции(_ документ: ДокументСсылокПакета, бюджет: БюджетПеречняАдресов? = nil) throws -> СобранныеСсылкиМиграции {
    let диагностика = бюджет != nil
    let сканер = try СканерСсылокПакета(документ, строгий: true, бюджет: бюджет)
    let первая = сканер.строки.first.map { сканер.текст($0.начало..<$0.телоКонец) }
    try сканер.проверитьБюджет()
    try требоватьСсылки(первая != "---" && первая != "+++", "нужен-адаптер-frontmatter")
    var токены: [ТокенСсылкиПакета] = [], определения: [String: [ТокенСсылкиПакета]] = [:]
    var защищённыеМетки: Set<String> = [], активныеМетки: Set<String> = []
    var узлы: [ЧерновикУзлаАдресов] = [], ошибки: [ОшибкаПеречняАдресов] = [], неизвестные: [Range<Int>] = []
    var естьВложеннаяПодпись = false
    func добавитьУзел(_ узел: ЧерновикУзлаАдресов) throws {
        guard let бюджет else { return }
        try сканер.проверитьБюджет()
        try требоватьСсылки(бюджет.учесть(текущий: &бюджет.числоУзлов, предел: бюджет.пределы.узлы), "предел-диагностического-обхода")
        узлы.append(узел)
    }
    func ошибка(_ код: String, _ диапазон: Range<Int>, неизвестно: Bool = false) throws {
        guard let бюджет else { throw ОтказСсылокПакета.условие(код) }
        try сканер.проверитьБюджет()
        try требоватьСсылки(бюджет.учесть(текущий: &бюджет.числоОшибок, предел: бюджет.пределы.ошибки), "предел-диагностического-обхода")
        ошибки.append(.init(код: код, диапазон: диапазон))
        if неизвестно { неизвестные.append(диапазон) }
    }
    func проверитьПодпись(_ диапазон: Range<Int>) throws {
        for номер in диапазон {
            try требоватьСсылки(сканер.потратить(), "предел-диагностического-обхода")
            if !сканер.скрыто[номер], [91, 60].contains(сканер.байты[номер]), !сканер.экранирован(номер) {
                if диагностика { try ошибка("нужен-адаптер-вложенной-подписи", диапазон, неизвестно: true) }
                else { естьВложеннаяПодпись = true }
                return
            }
        }
    }
    for строка in сканер.строки {
        try требоватьСсылки(сканер.потратить(), "предел-диагностического-обхода")
        guard let токен = сканер.определение(строка), let метка = токен.меткаОпределения else { try сканер.проверитьБюджет(); continue }
        try сканер.проверитьБюджет()
        if определения[метка] != nil { try ошибка("повторное-reference-определение", токен.целиком) }
        определения[метка, default: []].append(токен)
        токены.append(токен); сканер.отметить(токен.целиком, &сканер.занято)
        try добавитьУзел(.init(вид: .определение, целиком: токен.целиком, адрес: токен.адрес, подпись: nil, метка: токен.метка, ключ: метка, изображение: false))
    }
    var курсор = 0
    while курсор < сканер.байты.count {
        try требоватьСсылки(сканер.потратить(), "предел-диагностического-обхода")
        if сканер.скрыто[курсор] || сканер.занято[курсор] { курсор += 1; continue }
        if сканер.совпало(курсор, "[[") && !сканер.экранирован(курсор) && (диагностика || !сканер.защищено[курсор]) {
            if !диагностика { throw ОтказСсылокПакета.условие("нужен-адаптер-wikilink") }
            var конец = курсор + 2
            while конец < сканер.байты.count && ![10, 13].contains(сканер.байты[конец]) && !сканер.совпало(конец, "]]") {
                try требоватьСсылки(сканер.потратить(), "предел-диагностического-обхода"); конец += 1
            }
            if сканер.совпало(конец, "]]") { конец += 2 }
            let диапазон = курсор..<конец
            try ошибка("нужен-адаптер-wikilink", диапазон, неизвестно: true)
            try добавитьУзел(.init(вид: .неподдержанный, целиком: диапазон, адрес: nil, подпись: nil, метка: nil, ключ: nil, изображение: false))
            сканер.отметить(диапазон, &сканер.занято); курсор = конец; continue
        }
        let изображение = сканер.байты[курсор] == 33 && курсор + 1 < сканер.байты.count && сканер.байты[курсор + 1] == 91
            && (!диагностика || !сканер.экранирован(курсор))
        let открытие = курсор + (изображение ? 1 : 0)
        if открытие < сканер.байты.count, сканер.байты[открытие] == 91, !сканер.экранирован(открытие), let закрытие = сканер.закрытьМетку(открытие) {
            let подпись = (открытие + 1)..<закрытие
            if закрытие + 1 < сканер.байты.count, сканер.байты[закрытие + 1] == 40 {
                if let токен = сканер.встроенная(курсор, скобка: закрытие + 1) {
                    токены.append(токен)
                    try проверитьПодпись(подпись)
                    try добавитьУзел(.init(вид: .встроенная, целиком: токен.целиком, адрес: токен.адрес, подпись: подпись, метка: nil, ключ: nil, изображение: изображение))
                    сканер.отметить(токен.целиком, &сканер.занято); курсор = токен.целиком.upperBound; continue
                } else if диагностика {
                    let предел = сканер.конецСтроки(курсор).тело
                    var конец = закрытие + 2
                    while конец < предел {
                        try требоватьСсылки(сканер.потратить(), "предел-диагностического-обхода")
                        let кандидат = [91, 60].contains(сканер.байты[конец])
                            || (сканер.байты[конец] == 33 && конец + 1 < предел && сканер.байты[конец + 1] == 91)
                        if кандидат && !сканер.экранирован(конец) { break }
                        конец += 1
                    }
                    let диапазон = курсор..<конец
                    try ошибка("неполная-встроенная-ссылка", диапазон, неизвестно: true)
                    try добавитьУзел(.init(вид: .неподдержанный, целиком: диапазон, адрес: nil, подпись: подпись, метка: nil, ключ: nil, изображение: изображение))
                    сканер.отметить(диапазон, &сканер.занято); курсор = конец; continue
                }
            }
            var ключ = сканер.ключМетки(сканер.текст(подпись)), конец = закрытие + 1
            var вид: ВидУзлаПеречняАдресов = .сокращённая, метка = подпись
            if конец < сканер.байты.count, сканер.байты[конец] == 91, let правый = сканер.закрытьМетку(конец) {
                метка = (конец + 1)..<правый
                if !метка.isEmpty { ключ = сканер.ключМетки(сканер.текст(метка)); вид = .полная }
                else { вид = .свёрнутая }
                конец = правый + 1
            }
            try сканер.проверитьБюджет()
            if определения[ключ] != nil || диагностика {
                let диапазон = курсор..<конец
                try проверитьПодпись(подпись)
                if определения[ключ] != nil {
                    try требоватьСсылки(сканер.потратить(диапазон.count), "предел-диагностического-обхода")
                    if диапазон.contains(where: { сканер.защищено[$0] }) { защищённыеМетки.insert(ключ) }
                    else { активныеМетки.insert(ключ) }
                } else { try ошибка("неразрешённая-reference-метка", диапазон, неизвестно: true) }
                if (определения[ключ]?.count ?? 0) > 1 { try ошибка("неоднозначная-reference-метка", диапазон, неизвестно: true) }
                try добавитьУзел(.init(вид: вид, целиком: диапазон, адрес: nil, подпись: подпись, метка: метка, ключ: ключ, изображение: изображение))
                сканер.отметить(диапазон, &сканер.занято); курсор = конец; continue
            }
        }
        try сканер.проверитьБюджет()
        курсор += 1
    }
    // Сохраняется старый отдельный residual pass после полного wikilink pass.
    var номер = 0
    while номер < сканер.байты.count {
        try требоватьСсылки(сканер.потратить(), "предел-диагностического-обхода")
        if !сканер.скрыто[номер] && !сканер.занято[номер] && (диагностика || !сканер.защищено[номер]),
           [91, 60].contains(сканер.байты[номер]), !сканер.экранирован(номер) {
            if !диагностика { throw ОтказСсылокПакета.условие("неподдержанный-остаток-Markdown") }
            var конец = номер + 1
            while конец < сканер.байты.count && ![10, 13].contains(сканер.байты[конец]) {
                try требоватьСсылки(сканер.потратить(), "предел-диагностического-обхода")
                if сканер.байты[номер] == 60 && сканер.байты[конец] == 62 { конец += 1; break }
                конец += 1
            }
            let диапазон = номер..<конец
            try ошибка("неподдержанный-остаток-Markdown", диапазон, неизвестно: true)
            try добавитьУзел(.init(вид: .неподдержанный, целиком: диапазон, адрес: nil, подпись: nil, метка: nil, ключ: nil, изображение: false))
            номер = конец; continue
        }
        номер += 1
    }
    try сканер.проверитьБюджет()
    // Новый guard закрывает ранее неучтённые вложенные адреса. Он не меняет
    // старую кратность targets и следует за прежними lexical/residual отказами.
    try требоватьСсылки(!естьВложеннаяПодпись, "нужен-адаптер-вложенной-подписи")
    return .init(сканер: сканер, токены: токены, защищённыеМетки: защищённыеМетки, активныеМетки: активныеМетки, узлы: узлы, ошибки: ошибки, неизвестные: неизвестные)
}

enum РешательСсылокПакета {
    static func диагностироватьРазрешение(_ документ: ДокументСсылокПакета, перечень: ПереченьАдресовДокумента,
        контекст: КонтекстКандидатовАдресов, ожидаемыйХэшКонтекста: String,
        пределы: ПределыКандидатовАдресов = .init()) -> КандидатыРазрешенияДокумента {
        let штатные = ПределыКандидатовАдресов()
        func верныйХэш(_ значение: String) -> Bool {
            значение.utf8.count == 64 && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
        }
        func неизвестно(_ причина: String) -> КандидатыРазрешенияДокумента {
            .init(путь: документ.путь.utf8.count <= 1024 ? документ.путь : "непроверенный-путь", хэшДокумента: верныйХэш(документ.sha256) ? документ.sha256 : "", хэшКонтекста: контекст.хэшСостава,
                вхождения: [], упоминания: [], неразобранныеУзлы: перечень.узлы.prefix(штатные.узлы).map(\.номер), ошибки: [причина], всеЗаявленныеУзлыУчтены: false)
        }
        guard документ.путь.utf8.count <= 1024, перечень.путь.utf8.count <= 1024,
              верныйХэш(документ.sha256), верныйХэш(перечень.заявленныйХэш), верныйХэш(ожидаемыйХэшКонтекста),
              (0...штатные.байтыДокумента).contains(пределы.байтыДокумента), (0...штатные.узлы).contains(пределы.узлы),
              (0...штатные.байтыАдреса).contains(пределы.байтыАдреса), (0...штатные.суммаАдресов).contains(пределы.суммаАдресов),
              (0...штатные.суммаКандидатов).contains(пределы.суммаКандидатов), (0...штатные.шаги).contains(пределы.шаги),
              документ.байты.count <= пределы.байтыДокумента, перечень.узлы.count <= пределы.узлы,
              перечень.ошибки.count <= штатные.узлы, перечень.ошибки.allSatisfy({ $0.код.utf8.count <= 256 }),
              ожидаемыйХэшКонтекста == контекст.хэшСостава,
              Data(перечень.путь.utf8) == Data(документ.путь.utf8), перечень.заявленныйХэш == документ.sha256,
              перечень.размер == документ.байты.count, перечень.хэшПроверен, перечень.обходЗавершён else { return неизвестно("не-подтверждён-вход-кандидатов-адресов") }
        let байты = Data(документ.байты)
        var шаги = пределы.шаги, суммаАдресов = 0, суммаКандидатов = 0
        func потратить(_ число: Int) throws {
            guard число >= 0, число <= шаги else { throw ОтказСсылокПакета.условие("предел-диагностики-кандидатов") }
            шаги -= число
        }
        func проверитьДиапазон(_ диапазон: Range<Int>) throws {
            try требоватьСсылки(диапазон.lowerBound >= 0 && диапазон.upperBound >= диапазон.lowerBound && диапазон.upperBound <= байты.count, "неверный-диапазон-перечня-кандидатов")
            for позиция in [диапазон.lowerBound, диапазон.upperBound] where позиция > 0 && позиция < байты.count {
                try требоватьСсылки(байты[позиция] & 0xC0 != 0x80, "разрыв-UTF8-диапазона-кандидатов")
            }
        }
        func обследовать(_ путь: String, в пространство: [Data: ВидУзлаМиграции], алиасы: Set<Data>) throws -> (вид: ВидУзлаМиграции?, граница: String?, алиас: Bool) {
            let точный = Data(путь.utf8); var предок = точный
            while true {
                try потратить(предок.count + 1)
                if алиасы.contains(предок) { return (пространство[точный], nil, true) }
                if let вид = пространство[предок], вид == .ссылка || вид == .внешняяГраница { return (пространство[точный], String(decoding: предок, as: UTF8.self), false) }
                if предок.isEmpty { break }
                предок = предок.lastIndex(of: 47).map { Data(предок[..<$0]) } ?? Data()
            }
            return (пространство[точный], nil, false)
        }
        func удаляется(_ путь: String) throws -> Bool {
            var предок = Data(путь.utf8)
            while !предок.isEmpty {
                try потратить(предок.count + 1)
                if контекст.удаляемые.contains(предок) { return true }
                предок = предок.lastIndex(of: 47).map { Data(предок[..<$0]) } ?? Data()
            }
            return false
        }
        do {
            try ИменаПутей.проверитьПуть(документ.путь)
            try потратить(документ.байты.count)
            try требоватьСсылки(хэшПутей(байты) == документ.sha256 && String(data: байты, encoding: .utf8) != nil, "дрейф-источника-кандидатов")
            let будущийДокумент = контекст.соответствия[Data(документ.путь.utf8)] ?? документ.путь
            let старыйДокумент = try обследовать(документ.путь, в: контекст.исходные, алиасы: контекст.исходныеАлиасы)
            let новыйДокумент = try обследовать(будущийДокумент, в: контекст.будущие, алиасы: контекст.будущиеАлиасы)
            try требоватьСсылки(старыйДокумент.вид == .файл && новыйДокумент.вид == .файл && !старыйДокумент.алиас && !новыйДокумент.алиас,
                "нет-точного-документа-пространства-кандидатов")
            var числоСвязей = 0
            for (номер, узел) in перечень.узлы.enumerated() {
                try потратить(1)
                try требоватьСсылки(узел.номер == номер && (номер == 0 || перечень.узлы[номер - 1].целиком.lowerBound <= узел.целиком.lowerBound), "неверные-номера-узлов-кандидатов")
                try проверитьДиапазон(узел.целиком)
                for диапазон in [узел.адрес, узел.подпись, узел.метка].compactMap({ $0 }) {
                    try проверитьДиапазон(диапазон)
                    try требоватьСсылки(диапазон.lowerBound >= узел.целиком.lowerBound && диапазон.upperBound <= узел.целиком.upperBound, "поддиапазон-вне-узла-кандидатов")
                }
                try требоватьСсылки(узел.определения.count <= пределы.узлы - числоСвязей, "предел-связей-кандидатов")
                числоСвязей += узел.определения.count
                var замеченные: Set<Int> = []
                for определение in узел.определения {
                    try потратить(1)
                    try требоватьСсылки((0..<перечень.узлы.count).contains(определение) && перечень.узлы[определение].вид == .определение
                        && замеченные.insert(определение).inserted, "неверная-связь-кандидатов")
                }
                let прямой = узел.вид == .определение || узел.вид == .встроенная
                try требоватьСсылки(прямой == (узел.адрес != nil), "нет-точного-вхождения-адреса")
            }
            var вхождения: [ВхождениеКандидатаАдреса] = [], номераВхождений: [Int: Int] = [:]
            var упоминания: [УпоминаниеКандидатаАдреса] = [], неразобранные: [Int] = []
            var ошибки = перечень.ошибки.map(\.код)
            for узел in перечень.узлы {
                try потратить(1)
                guard let диапазон = узел.адрес else { continue }
                var вид: ВидКандидатаАдреса = .отказ, ошибка: String?, старая: String?, новая: String?, путьАдреса: String?, граница: String?
                var старыйВид: ВидУзлаМиграции?, хэшАдреса: String?, хэшСуффикса: String?, сохранён = false
                var суффикс = диапазон.upperBound..<диапазон.upperBound
                if диапазон.count > пределы.байтыАдреса { ошибка = "предел-длины-адреса-кандидата" }
                else {
                    try требоватьСсылки(диапазон.count <= пределы.суммаАдресов - суммаАдресов, "предел-диагностики-кандидатов")
                    суммаАдресов += диапазон.count
                    guard диапазон.count <= шаги / 8 else { throw ОтказСсылокПакета.условие("предел-диагностики-кандидатов") }
                    try потратить(диапазон.count * 8)
                    let сырыеБайты = байты.subdata(in: диапазон), сырое = String(decoding: сырыеБайты, as: UTF8.self)
                    хэшАдреса = хэшПутей(сырыеБайты)
                    let части = АдресСсылкиПакета.разделить(сырое)
                    суффикс = (диапазон.upperBound - части.1.utf8.count)..<диапазон.upperBound
                    хэшСуффикса = хэшПутей(байты.subdata(in: суффикс))
                    do {
                        let разбор = try АдресСсылкиПакета.разобрать(сырое, документ: документ.путь, побайтово: true)
                        if let цель = разбор.путь {
                            старая = цель
                            let исход = try обследовать(цель, в: контекст.исходные, алиасы: контекст.исходныеАлиасы)
                            старыйВид = исход.вид; граница = исход.граница
                            if исход.алиас { ошибка = "алиас-исходной-цели-кандидата" }
                            else if исход.граница != nil { вид = .непрозрачнаяГраница; ошибка = "не-проверена-граница-цели-кандидата" }
                            else if исход.вид == nil { ошибка = "нет-точной-старой-цели" }
                            else if try удаляется(цель) { вид = .удаляемый; ошибка = "цель-удаляется-нужно-каноническое-происхождение" }
                            else {
                                let будущая = контекст.соответствия[Data(цель.utf8)] ?? цель
                                новая = будущая
                                let конечный = try обследовать(будущая, в: контекст.будущие, алиасы: контекст.будущиеАлиасы)
                                if конечный.алиас { ошибка = "алиас-будущей-цели-кандидата" }
                                else if конечный.граница != nil { вид = .непрозрачнаяГраница; граница = конечный.граница; ошибка = "не-проверена-будущая-граница" }
                                else if конечный.вид != исход.вид { ошибка = "нет-точной-будущей-цели-или-совпадения-вида" }
                                else {
                                    let угловое = диапазон.lowerBound > узел.целиком.lowerBound && диапазон.upperBound < узел.целиком.upperBound
                                        && байты[диапазон.lowerBound - 1] == 60 && байты[диапазон.upperBound] == 62
                                    if let прежний = try? АдресСсылкиПакета.разобрать(сырое, документ: будущийДокумент, побайтово: true),
                                       прежний.путь.map({ Data($0.utf8) == Data(будущая.utf8) }) == true {
                                        путьАдреса = части.0; сохранён = true
                                    } else {
                                        var кандидат = АдресСсылкиПакета.относительныйПуть(будущая, документ: будущийДокумент, угловое: угловое)
                                        if исход.вид == .каталог && части.0.utf8.last == 47 && кандидат.utf8.last != 47 { кандидат += "/" }
                                        путьАдреса = кандидат
                                    }
                                    let обратный = try АдресСсылкиПакета.разобрать((путьАдреса ?? "") + разбор.суффикс, документ: будущийДокумент, побайтово: true)
                                    try требоватьСсылки(обратный.путь.map({ Data($0.utf8) == Data(будущая.utf8) }) == true, "неверный-обратный-адрес-кандидата")
                                    вид = .локальный
                                }
                            }
                        } else { вид = .внешний }
                    } catch {
                        if case let ОтказСсылокПакета.условие(причина) = error {
                            if причина == "предел-диагностики-кандидатов" { throw error }
                            ошибка = причина
                        } else { ошибка = "непредвиденный-отказ-адреса-кандидата" }
                        путьАдреса = nil; сохранён = false
                    }
                }
                let размер = 256 + (старая?.utf8.count ?? 0) + (новая?.utf8.count ?? 0) + (путьАдреса?.utf8.count ?? 0) + (граница?.utf8.count ?? 0)
                try требоватьСсылки(размер <= пределы.суммаКандидатов - суммаКандидатов, "предел-диагностики-кандидатов")
                суммаКандидатов += размер
                номераВхождений[узел.номер] = вхождения.count
                вхождения.append(.init(номерУзла: узел.номер, адрес: диапазон, суффикс: суффикс, хэшАдреса: хэшАдреса, хэшСуффикса: хэшСуффикса,
                    вид: вид, прежняяЦель: старая, видПрежнейЦели: старыйВид, будущаяЦель: новая, граница: граница, новыйПутьАдреса: путьАдреса, сохранёнИсходныйПуть: сохранён, ошибка: ошибка))
            }
            for узел in перечень.узлы {
                try потратить(1)
                switch узел.вид {
                case .полная, .свёрнутая, .сокращённая:
                    let номер = узел.определения.count == 1 ? узел.определения.first.flatMap { номераВхождений[$0] } : nil
                    let ошибка = узел.определения.isEmpty ? "неразрешённая-reference-метка"
                        : узел.определения.count > 1 ? "неоднозначная-reference-метка"
                        : номер.flatMap { вхождения[$0].ошибка }
                    упоминания.append(.init(номерУзла: узел.номер, определения: узел.определения, вхождение: номер, ошибка: ошибка))
                case .неподдержанный: неразобранные.append(узел.номер)
                case .определение, .встроенная: break
                }
            }
            if !перечень.синтаксисПолностьюРаспознан { ошибки.append("остались-неизвестные-области-перечня") }
            return .init(путь: документ.путь, хэшДокумента: документ.sha256, хэшКонтекста: контекст.хэшСостава,
                вхождения: вхождения, упоминания: упоминания, неразобранныеУзлы: неразобранные, ошибки: ошибки,
                всеЗаявленныеУзлыУчтены: вхождения.count + упоминания.count + неразобранные.count == перечень.узлы.count)
        } catch {
            if case let ОтказСсылокПакета.условие(причина) = error { return неизвестно(причина) }
            return неизвестно("непредвиденный-отказ-диагностики-кандидатов")
        }
    }
    static func перечислитьАдреса(_ документ: ДокументСсылокПакета, пределы: ПределыПеречняАдресов = .init()) -> ПереченьАдресовДокумента {
        var хэшПроверен = false
        func неизвестно(_ код: String) -> ПереченьАдресовДокумента {
            .init(путь: документ.путь, заявленныйХэш: документ.sha256, размер: документ.байты.count, хэшПроверен: хэшПроверен,
                обходЗавершён: false, синтаксисПолностьюРаспознан: false, узлы: [], ошибки: [.init(код: код, диапазон: 0..<документ.байты.count)],
                неизвестныеДиапазоны: [0..<документ.байты.count], скрытыеДиапазоны: [], эвристическиЗащищённыеДиапазоны: [], неподдержанныеКонтейнеры: [])
        }
        let штатные = ПределыПеречняАдресов()
        guard (0...штатные.байты).contains(пределы.байты), (0...штатные.строки).contains(пределы.строки),
              (0...штатные.узлы).contains(пределы.узлы), (0...штатные.ошибки).contains(пределы.ошибки), (0...штатные.шаги).contains(пределы.шаги),
              документ.байты.count <= пределы.байты else { return неизвестно("предел-входа-диагностики") }
        var числоСтрок = документ.байты.isEmpty || документ.байты.last != 10 ? 1 : 0
        for байт in документ.байты where байт == 10 {
            числоСтрок += 1
            if числоСтрок > пределы.строки { return неизвестно("предел-строк-диагностики") }
        }
        guard числоСтрок <= пределы.строки else { return неизвестно("предел-строк-диагностики") }
        хэшПроверен = хэшПутей(документ.байты) == документ.sha256
        guard хэшПроверен else { return неизвестно("дрейф-байтов-Markdown") }
        let бюджет = БюджетПеречняАдресов(пределы)
        do {
            try ИменаПутей.проверитьПуть(документ.путь)
            let сбор = try собратьСсылкиМиграции(документ, бюджет: бюджет), сканер = сбор.сканер
            try сканер.проверитьБюджет()
            let упорядоченные = сбор.узлы.sorted { $0.целиком.lowerBound < $1.целиком.lowerBound }
            var определения: [String: [Int]] = [:]
            for (номер, узел) in упорядоченные.enumerated() where узел.вид == .определение {
                if let ключ = узел.ключ { определения[ключ, default: []].append(номер) }
            }
            var узлы: [УзелПеречняАдресов] = []
            for (номер, узел) in упорядоченные.enumerated() {
                try сканер.проверитьБюджет()
                let кандидаты = узел.вид == .определение ? [] : узел.ключ.flatMap { определения[$0] } ?? []
                try требоватьСсылки(бюджет.учесть(кандидаты.count, текущий: &бюджет.числоСвязей, предел: пределы.узлы), "предел-диагностического-обхода")
                try требоватьСсылки(сканер.потратить(узел.целиком.count), "предел-диагностического-обхода")
                let защищён = узел.целиком.contains { сканер.защищено[$0] }
                try требоватьСсылки(сканер.потратить(узел.целиком.count), "предел-диагностического-обхода")
                let контейнер = узел.целиком.contains { сканер.неподдержано[$0] }
                узлы.append(.init(номер: номер, вид: узел.вид, целиком: узел.целиком, адрес: узел.адрес, подпись: узел.подпись, метка: узел.метка,
                    ключМетки: узел.ключ, определения: кандидаты, изображение: узел.изображение, эвристическиЗащищён: защищён, неподдержанныйКонтейнер: контейнер))
            }
            func диапазоны(_ маска: [Bool]) throws -> [Range<Int>] {
                try требоватьСсылки(сканер.потратить(маска.count), "предел-диагностического-обхода")
                var итог: [Range<Int>] = [], начало: Int?
                for номер in 0...маска.count {
                    let установлен = номер < маска.count && маска[номер]
                    if установлен && начало == nil { начало = номер }
                    if !установлен, let открытие = начало {
                        try требоватьСсылки(бюджет.учесть(текущий: &бюджет.числоДиапазонов, предел: пределы.узлы), "предел-диагностического-обхода")
                        итог.append(открытие..<номер); начало = nil
                    }
                }
                return итог
            }
            let скрытые = try диапазоны(сканер.скрыто), защищённые = try диапазоны(сканер.защищено), контейнеры = try диапазоны(сканер.неподдержано)
            return .init(путь: документ.путь, заявленныйХэш: документ.sha256, размер: документ.байты.count, хэшПроверен: true,
                обходЗавершён: true, синтаксисПолностьюРаспознан: сбор.ошибки.isEmpty && контейнеры.isEmpty, узлы: узлы, ошибки: сбор.ошибки,
                неизвестныеДиапазоны: сбор.неизвестные, скрытыеДиапазоны: скрытые, эвристическиЗащищённыеДиапазоны: защищённые, неподдержанныеКонтейнеры: контейнеры)
        } catch {
            let код: String
            if case let ОтказСсылокПакета.условие(причина) = error { код = причина }
            else { код = "внутренняя-ошибка-диагностики" }
            return неизвестно(бюджет.исчерпан ? "предел-диагностического-обхода" : код)
        }
    }
    // Новый dry-вход не ослабляет девятипарный контракт разрешить(...).
    static func разрешитьМиграцию(
        документы: [ДокументСсылокПакета], ожидаемыеПути: [String],
        отображения: [СтрокаОбщегоОтображения], исходныеПути: Set<Data>, конечныеПути: Set<Data>,
        удалённыеПути: Set<Data> = [], дословныеДокументы: Set<Data> = []
    ) throws -> [String: РазрешённыйДокументМиграции] {
        let фактические = документы.map { Data($0.путь.utf8) }.sorted { $0.lexicographicallyPrecedes($1) }
        let ожидаемые = ожидаемыеПути.map { Data($0.utf8) }.sorted { $0.lexicographicallyPrecedes($1) }
        try требоватьСсылки(фактические == ожидаемые && Set(фактические).count == фактические.count,
            "неполный-или-повторный-Markdown-инвентарь")
        var карта: [Data: String] = [:]
        for пара in отображения {
            try ИменаПутей.проверитьПуть(пара.исходный); try ИменаПутей.проверитьПуть(пара.целевой)
            try требоватьСсылки(карта.updateValue(пара.целевой, forKey: Data(пара.исходный.utf8)) == nil, "повторное-отображение")
            try требоватьСсылки(исходныеПути.contains(Data(пара.исходный.utf8)) && конечныеПути.contains(Data(пара.целевой.utf8)), "отображение-вне-пространства")
        }
        func будущееИмя(_ путь: String) -> String { карта[Data(путь.utf8)] ?? путь }
        func относительный(_ цель: String, от документа: String, угловое: Bool) -> String {
            АдресСсылкиПакета.относительныйПуть(цель, документ: документа, угловое: угловое)
        }
        var результаты: [String: РазрешённыйДокументМиграции] = [:]
        for документ in документы.sorted(by: { порядокПутей($0.путь, $1.путь) }) {
            let исходныеБайты = Data(документ.байты)
            try требоватьСсылки(исходныеПути.contains(Data(документ.путь.utf8)) && хэшПутей(документ.байты) == документ.sha256, "дрейф-байтов-Markdown")
            try требоватьСсылки(результаты[документ.путь] == nil, "Unicode-алиас-документа")
            if дословныеДокументы.contains(Data(документ.путь.utf8)) || ИменаПутей.имеетПрефикс(документ.путь, "Источники/") {
                результаты[документ.путь] = .init(байтыПосле: исходныеБайты, целиПосле: [], полнотаПроверена: true)
                continue
            }
            let будущийДокумент = будущееИмя(документ.путь)
            try требоватьСсылки(конечныеПути.contains(Data(будущийДокумент.utf8)), "нет-будущего-документа")
            let сбор = try собратьСсылкиМиграции(документ), сканер = сбор.сканер
            let токены = сбор.токены, защищённыеМетки = сбор.защищённыеМетки, активныеМетки = сбор.активныеМетки
            var правки: [ПравкаСсылкиПакета] = [], цели: [String] = []
            for токен in токены.sorted(by: { $0.адрес.lowerBound < $1.адрес.lowerBound }) {
                let защищён = токен.целиком.contains(where: { сканер.защищено[$0] })
                if защищён && токен.меткаОпределения.map({ активныеМетки.contains($0) }) != true { continue }
                let сырое = сканер.текст(токен.адрес)
                let адрес = try АдресСсылкиПакета.разобрать(сырое, документ: документ.путь, побайтово: true)
                guard let прежняяЦель = адрес.путь else { continue }
                try требоватьСсылки(исходныеПути.contains(Data(прежняяЦель.utf8)), "нет-точной-старой-цели")
                try требоватьСсылки(!удалённыеПути.contains(Data(прежняяЦель.utf8)), "цель-удаляется-нужно-каноническое-происхождение")
                let будущаяЦель = будущееИмя(прежняяЦель)
                try требоватьСсылки(конечныеПути.contains(Data(будущаяЦель.utf8)), "нет-точной-будущей-цели")
                try требоватьСсылки(!токен.целиком.contains(where: { сканер.неподдержано[$0] }), "нужен-адаптер-container")
                цели.append(будущаяЦель)
                if let ужеРазрешён = try? АдресСсылкиПакета.разобрать(сырое, документ: будущийДокумент, побайтово: true),
                   let ужеЦель = ужеРазрешён.путь, АдресСсылкиПакета.точно(ужеЦель, будущаяЦель) { continue }
                try требоватьСсылки(!защищён, "definition-в-дословной-области")
                if let метка = токен.меткаОпределения, защищённыеМетки.contains(метка) {
                    throw ОтказСсылокПакета.условие("definition-меняет-дословную-ссылку")
                }
                let новое = относительный(будущаяЦель, от: будущийДокумент, угловое: токен.угловое) + адрес.суффикс
                let обратнаяЦель = try АдресСсылкиПакета.разобрать(новое, документ: будущийДокумент, побайтово: true).путь
                try требоватьСсылки(обратнаяЦель.map { АдресСсылкиПакета.точно($0, будущаяЦель) } == true, "неверный-будущий-адрес")
                правки.append(.init(диапазон: токен.адрес, прежние: исходныеБайты.subdata(in: токен.адрес), новые: Data(новое.utf8)))
            }
            for номер in правки.indices where номер > 0 {
                try требоватьСсылки(правки[номер - 1].диапазон.upperBound <= правки[номер].диапазон.lowerBound, "пересекающиеся-правки")
            }
            var будущие = исходныеБайты
            for правка in правки.reversed() { будущие.replaceSubrange(правка.диапазон, with: правка.новые) }
            результаты[документ.путь] = .init(байтыПосле: будущие, целиПосле: цели, полнотаПроверена: true)
        }
        return результаты
    }

    static func обновитьСвежесть(_ данные: Data, путь: String, время: String) throws -> Data {
        guard let текст = String(data: данные, encoding: .utf8) else { throw ОтказСсылокПакета.условие("не-UTF8-recency") }
        let сканер = try СканерСсылокПакета(ДокументСсылокПакета(путь: путь, байты: данные, sha256: хэшПутей(данные)))
        let шаблон = #"(?:\A|\r?\n)<!-- FUM-MD-RECENCY:BEGIN -->\r?\n<!-- last-content-edit: ([^>]+) -->\r?\n<!-- content-sha256: sha256:([0-9a-f]{64}) -->\r?\n<!-- FUM-MD-RECENCY:END -->\r?\n?\z"#
        let выражение = try NSRegularExpression(pattern: шаблон)
        let совпадение = выражение.firstMatch(in: текст, range: NSRange(текст.startIndex..., in: текст))
        var содержимое = текст
        if let совпадение, let диапазон = Range(совпадение.range, in: текст) {
            let начало = текст[..<диапазон.lowerBound].utf8.count
            guard !сканер.скрыто.dropFirst(начало).allSatisfy({ $0 }) else {
                throw ОтказСсылокПакета.условие("метка-recency-в-ограде")
            }
            содержимое = String(текст[..<диапазон.lowerBound])
        } else {
            let видимые = сканер.байты.indices.map { сканер.скрыто[$0] ? UInt8(32) : сканер.байты[$0] }
            let видимыйТекст = String(decoding: видимые, as: UTF8.self)
            if видимыйТекст.contains("FUM-MD-RECENCY:BEGIN") || видимыйТекст.contains("FUM-MD-RECENCY:END") {
                throw ОтказСсылокПакета.условие("повреждённая-recency")
            }
        }
        if !содержимое.hasSuffix("\n") { содержимое += "\n" }
        var дляХэша = содержимое.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        let части = ИменаПутей.компоненты(путь)
        if части.count == 3, части[0] == "Журнал", части[2] == "отчёт.md" {
            let начал = дляХэша.components(separatedBy: "<!-- FUM-CHECK-RUNS:BEGIN ").count - 1
            let концов = дляХэша.components(separatedBy: "<!-- FUM-CHECK-RUNS:END -->").count - 1
            if начал != 0 || концов != 0 {
                let шаблонЗапусков = #"(?ms)^<!-- FUM-CHECK-RUNS:BEGIN (?:состояние=открыт; каталог=материалы/запуски-проверок|состояние=закрыт; снимок=материалы/запуски-проверок/снимок\.json; sha256=sha256:[0-9a-f]{64}) -->\n.*?\n<!-- FUM-CHECK-RUNS:END -->$"#
                let выражениеЗапусков = try NSRegularExpression(pattern: шаблонЗапусков)
                let найденные = выражениеЗапусков.matches(in: дляХэша, range: NSRange(дляХэша.startIndex..., in: дляХэша))
                guard начал == 1, концов == 1, найденные.count == 1, let диапазон = Range(найденные[0].range, in: дляХэша) else {
                    throw ОтказСсылокПакета.условие("повреждённый-блок-проверок-recency")
                }
                дляХэша.replaceSubrange(диапазон, with: "<!-- FUM-CHECK-RUNS:MANAGED -->")
            }
        }
        let хэш = хэшПутей(Data(дляХэша.utf8))
        return Data((содержимое + "\n<!-- FUM-MD-RECENCY:BEGIN -->\n<!-- last-content-edit: \(время) -->\n<!-- content-sha256: sha256:\(хэш) -->\n<!-- FUM-MD-RECENCY:END -->\n").utf8)
    }

    // Это консервативный detector для неподдержанных конструкций,
    // а не дополнительный способ разрешения адреса.
    private static func числовыеСущности(_ значение: String) -> String {
        guard let выражение = try? NSRegularExpression(pattern: #"&#(?:[xX]([0-9a-fA-F]+)|([0-9]+));?"#) else { return значение }
        var результат = значение
        for совпадение in выражение.matches(in: значение, range: NSRange(значение.startIndex..., in: значение)).reversed() {
            let шестнадцатеричное = совпадение.range(at: 1).location != NSNotFound
            let позиция = шестнадцатеричное ? 1 : 2
            guard let диапазонЧисла = Range(совпадение.range(at: позиция), in: значение),
                  let код = UInt32(значение[диапазонЧисла], radix: шестнадцатеричное ? 16 : 10),
                  let знак = UnicodeScalar(код), let диапазон = Range(совпадение.range, in: результат) else { continue }
            результат.replaceSubrange(диапазон, with: String(знак))
        }
        return результат
    }

    private static func похожеНаПакет(
        _ значение: String, пары: [ОтображениеПути]
    ) -> Bool {
        let снятое = АдресСсылкиПакета.снятьЭкранирование(значение)
        let числовое = числовыеСущности(снятое)
        let варианты = [значение, снятое, числовое, числовое.removingPercentEncoding ?? числовое]
            .map(АдресСсылкиПакета.ключ)
        let имена = пары.flatMap { [$0.исходный, $0.целевой] }.flatMap {
            let имя = ($0 as NSString).lastPathComponent
            return [имя, (имя as NSString).deletingPathExtension]
        }.map(АдресСсылкиПакета.ключ)
        return варианты.contains { вариант in
            имена.contains { !($0.isEmpty) && вариант.contains($0) }
        }
    }

    static func разрешить(
        документы: [ДокументСсылокПакета],
        ожидаемыеПути: [String],
        пары: [ОтображениеПути],
        разрешённыеДокументы: Set<String>,
        проверитьАдрес: (String) throws -> Void
    ) throws -> [ИзменениеСсылокПакета] {
        try требоватьСсылки(пары.count == 9, "нужны-девять-пар")
        let упорядоченные = документы.sorted {
            порядокПутей($0.путь, $1.путь)
        }
        let фактические = упорядоченные.map(\.путь)
        let ожидаемые = ожидаемыеПути.sorted(by: порядокПутей)
        try требоватьСсылки(
            фактические.map { Data($0.utf8) }
                == ожидаемые.map { Data($0.utf8) }
                && Set(фактические.map { Data($0.utf8) }).count
                    == фактические.count,
            "неполный-или-повторный-Markdown-инвентарь"
        )

        var результаты: [ИзменениеСсылокПакета] = []

        // Один общий проход по переданному полному inventory для всех девяти пар.
        for документ in упорядоченные {
            try требоватьСсылки(
                хэшПутей(документ.байты) == документ.sha256,
                "дрейф-байтов-Markdown"
            )
            let сканер = try СканерСсылокПакета(документ)
            var токены: [ТокенСсылкиПакета] = []
            var определения: [String: [ТокенСсылкиПакета]] = [:]
            var защищённыеМетки: Set<String> = []

            for строка in сканер.строки {
                guard let токен = сканер.определение(строка) else { continue }
                токены.append(токен)
                определения[токен.меткаОпределения!, default: []].append(токен)
                сканер.отметить(токен.целиком, &сканер.занято)
            }

            for группа in определения.values where группа.count > 1 {
                if группа.contains(where: {
                    похожеНаПакет(сканер.текст($0.адрес), пары: пары)
                }) {
                    throw ОтказСсылокПакета.условие(
                        "повторное-относящееся-reference-определение"
                    )
                }
            }

            var курсор = 0
            while курсор < сканер.байты.count {
                if сканер.скрыто[курсор] || сканер.занято[курсор] {
                    курсор += 1
                    continue
                }
                if сканер.совпало(курсор, "[[")
                    && !сканер.экранирован(курсор) {
                    let предел = сканер.конецСтроки(курсор).тело
                    var конец = курсор + 2
                    while конец < предел && !сканер.совпало(конец, "]]") {
                        конец += 1
                    }
                    let цель = сканер.текст((курсор + 2)..<конец)
                        .components(separatedBy: "|")[0]
                        .components(separatedBy: "#")[0]
                    try требоватьСсылки(
                        !похожеНаПакет(цель, пары: пары),
                        "относящийся-wikilink"
                    )
                    курсор = конец < предел ? конец + 2 : предел
                    continue
                }

                let изображение = сканер.байты[курсор] == 33
                    && курсор + 1 < сканер.байты.count
                    && сканер.байты[курсор + 1] == 91
                let открытие = курсор + (изображение ? 1 : 0)
                if открытие < сканер.байты.count,
                   сканер.байты[открытие] == 91,
                   !сканер.экранирован(открытие),
                   let закрытие = сканер.закрытьМетку(открытие) {
                    if закрытие + 1 < сканер.байты.count,
                       сканер.байты[закрытие + 1] == 40,
                       let токен = сканер.встроенная(
                           курсор, скобка: закрытие + 1
                       ) {
                        токены.append(токен)
                        сканер.отметить(токен.целиком, &сканер.занято)
                        курсор = токен.целиком.upperBound
                        continue
                    }

                    var ключ = сканер.ключМетки(
                        сканер.текст((открытие + 1)..<закрытие)
                    )
                    var конец = закрытие + 1
                    if конец < сканер.байты.count,
                       сканер.байты[конец] == 91,
                       let правый = сканер.закрытьМетку(конец) {
                        if правый > конец + 1 {
                            ключ = сканер.ключМетки(
                                сканер.текст((конец + 1)..<правый)
                            )
                        }
                        конец = правый + 1
                    }
                    if определения[ключ] != nil {
                        if (курсор..<конец).contains(where: { сканер.защищено[$0] }) { защищённыеМетки.insert(ключ) }
                        сканер.отметить(курсор..<конец, &сканер.занято)
                        курсор = конец
                        continue
                    }
                }
                курсор += 1
            }

            // Неразобранная относящаяся конструкция никогда не становится нулём.
            for строка in сканер.строки {
                let остаток = строка.начало..<строка.телоКонец
                let видимые = остаток.map { номер -> UInt8 in
                    сканер.скрыто[номер] || сканер.занято[номер]
                        ? 32 : сканер.байты[номер]
                }
                let текст = String(decoding: видимые, as: UTF8.self)
                let синтаксис = текст.contains("[") || текст.contains("<")
                    || текст.range(
                        of: #"(?i)\b(?:href|src)[ \t]*="#,
                        options: .regularExpression
                    ) != nil
                if синтаксис && (
                    похожеНаПакет(текст, пары: пары)
                        || текст.contains("&#")
                ) {
                    throw ОтказСсылокПакета.условие(
                        "относящийся-неподдержанный-Markdown"
                    )
                }
            }

            let остаточныеБайты = сканер.байты.indices.map { номер -> UInt8 in
                сканер.скрыто[номер] || сканер.занято[номер] ? 32 : сканер.байты[номер]
            }
            for абзац in String(decoding: остаточныеБайты, as: UTF8.self).components(separatedBy: "\n\n") {
                if абзац.contains("<"), абзац.range(of: #"(?i)\b(?:href|src)\s*="#, options: .regularExpression) != nil,
                   абзац.range(of: #"&(?:#[0-9]+|#[xX][0-9A-Fa-f]+|[A-Za-z][A-Za-z0-9]*);"#, options: .regularExpression) != nil,
                   похожеНаПакет(абзац, пары: пары) {
                    throw ОтказСсылокПакета.условие("неподдержанные-HTML-entities-адреса")
                }
                if (абзац.contains("[") || абзац.contains("<")) && похожеНаПакет(абзац, пары: пары) {
                    throw ОтказСсылокПакета.условие("относящийся-многострочный-остаток")
                }
            }

            var правки: [ПравкаСсылкиПакета] = []
            for токен in токены.sorted(by: {
                $0.адрес.lowerBound < $1.адрес.lowerBound
            }) {
                let сырой = сканер.текст(токен.адрес)
                let адрес: АдресСсылкиПакета.Разбор
                do { адрес = try АдресСсылкиПакета.разобрать(сырой, документ: документ.путь) }
                catch {
                    if похожеНаПакет(сырой, пары: пары) { throw error }
                    continue
                }
                if let путь = адрес.путь { try проверитьАдрес(путь) }
                guard let новый = try АдресСсылкиПакета.замена(
                    адрес, документ: документ.путь,
                    пары: пары, угловое: токен.угловое
                ) else { continue }

                if let метка = токен.меткаОпределения, защищённыеМетки.contains(метка) {
                    throw ОтказСсылокПакета.условие("definition-меняет-дословную-ссылку")
                }

                try требоватьСсылки(
                    !токен.целиком.contains { сканер.неподдержано[$0] },
                    "относящийся-неподдержанный-container"
                )
                try требоватьСсылки(
                    !токен.целиком.contains { сканер.защищено[$0] },
                    "ссылка-в-дословной-области"
                )
                try требоватьСсылки(
                    Set(разрешённыеДокументы.map { Data($0.utf8) }).contains(Data(документ.путь.utf8)),
                    "новый-неразрешённый-документ-ссылки"
                )
                правки.append(.init(
                    диапазон: токен.адрес,
                    прежние: документ.байты.subdata(in: токен.адрес),
                    новые: Data(новый.utf8)
                ))
            }

            for номер in правки.indices where номер > 0 {
                try требоватьСсылки(
                    правки[номер - 1].диапазон.upperBound
                        <= правки[номер].диапазон.lowerBound,
                    "пересекающиеся-правки"
                )
            }
            if правки.isEmpty { continue }
            var будущие = Data(документ.байты)
            for правка in правки.reversed() {
                будущие.replaceSubrange(правка.диапазон, with: правка.новые)
            }
            результаты.append(.init(
                путь: документ.путь,
                исходныйХэш: документ.sha256,
                правки: правки,
                будущиеБайты: будущие
            ))
        }
        return результаты
    }

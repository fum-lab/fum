import Foundation

struct ДокументСсылокПакета: Sendable {
    let путь: String
    let байты: Data
    let sha256: String
}

struct ПравкаСсылкиПакета: Sendable {
    let диапазон: Range<Int>       // UTF-8, относительно исходных байтов
    let прежние: Data
    let новые: Data
}

struct ИзменениеСсылокПакета: Sendable {
    let путь: String
    let исходныйХэш: String
    let правки: [ПравкаСсылкиПакета]
    let будущиеБайты: Data
}

enum ОтказСсылокПакета: Error {
    case условие(String)
}

private func требоватьСсылки(
    _ условие: Bool, _ причина: String
) throws {
    if !условие { throw ОтказСсылокПакета.условие(причина) }
}

// Сопоставление имени не подменяет точное совпадение UTF-8.
private enum АдресСсылкиПакета {
    struct Разбор {
        let путь: String?
        let суффикс: String
    }

    static func точно(_ левый: String, _ правый: String) -> Bool {
        левый.utf8.elementsEqual(правый.utf8)
    }

    static func ключ(_ значение: String) -> String {
        значение.precomposedStringWithCanonicalMapping
            .folding(
                options: [.caseInsensitive],
                locale: Locale(identifier: "en_US_POSIX")
            )
            .precomposedStringWithCanonicalMapping
    }

    static func снятьЭкранирование(_ значение: String) -> String {
        let знаки = Array(значение.unicodeScalars)
        var результат = ""
        var номер = 0
        func пунктуация(_ код: UInt32) -> Bool {
            (33...47).contains(код) || (58...64).contains(код)
                || (91...96).contains(код) || (123...126).contains(код)
        }
        while номер < знаки.count {
            if знаки[номер].value == 92,
               номер + 1 < знаки.count,
               пунктуация(знаки[номер + 1].value) {
                номер += 1
            }
            результат.unicodeScalars.append(знаки[номер])
            номер += 1
        }
        return результат
    }

    static func разделить(_ значение: String) -> (String, String) {
        let байты = Array(значение.utf8)
        var косые = 0
        for номер in байты.indices {
            if [35, 63].contains(байты[номер]), косые % 2 == 0 {
                return (
                    String(decoding: байты[..<номер], as: UTF8.self),
                    String(decoding: байты[номер...], as: UTF8.self)
                )
            }
            косые = байты[номер] == 92 ? косые + 1 : 0
        }
        return (значение, "")
    }

    private static func цифра(_ байт: UInt8) -> UInt8? {
        switch байт {
        case 48...57: байт - 48
        case 65...70: байт - 55
        case 97...102: байт - 87
        default: nil
        }
    }

    static func декодировать(_ значение: String) throws -> String {
        let вход = Array(значение.utf8)
        var выход: [UInt8] = []
        var номер = 0
        while номер < вход.count {
            if вход[номер] != 37 {
                выход.append(вход[номер])
                номер += 1
                continue
            }
            guard номер + 2 < вход.count,
                  let старшая = цифра(вход[номер + 1]),
                  let младшая = цифра(вход[номер + 2]) else {
                throw ОтказСсылокПакета.условие("неверное-percent-кодирование")
            }
            let байт = старшая * 16 + младшая
            try требоватьСсылки(
                байт != 47 && байт != 92,
                "закодированный-разделитель"
            )
            выход.append(байт)
            номер += 3
        }
        guard let текст = String(bytes: выход, encoding: .utf8) else {
            throw ОтказСсылокПакета.условие("неверный-UTF8-адрес")
        }
        try требоватьСсылки(
            !текст.contains("\\")
                && !текст.unicodeScalars.contains {
                    CharacterSet.controlCharacters.contains($0)
                },
            "небезопасный-адрес"
        )
        let прежние = значение.split(
            separator: "/", omittingEmptySubsequences: false
        )
        let новые = текст.split(
            separator: "/", omittingEmptySubsequences: false
        )
        try требоватьСсылки(
            прежние.count == новые.count,
            "изменён-разделитель"
        )
        for (прежний, новый) in zip(прежние, новые) {
            try требоватьСсылки(
                !(прежний.contains("%") && (новый == "." || новый == "..")),
                "закодированный-точечный-сегмент"
            )
        }
        return текст
    }

    static func разобрать(
        _ сырое: String, документ: String
    ) throws -> Разбор {
        let (сыройПуть, суффикс) = разделить(сырое)
        let путь = снятьЭкранирование(сыройПуть)

        try требоватьСсылки(
            !путь.lowercased().hasPrefix("file:")
                && путь.range(
                    of: #"^[A-Za-z]:"#,
                    options: .regularExpression
                ) == nil,
            "абсолютный-file-или-Windows-адрес"
        )
        if путь.hasPrefix("//") || путь.range(
            of: #"^[A-Za-z][A-Za-z0-9+.-]*:"#,
            options: .regularExpression
        ) != nil {
            return Разбор(путь: nil, суффикс: суффикс)
        }

        // HTML entity decoding — самостоятельный адаптер, а не догадка.
        try требоватьСсылки(
            путь.range(
                of: #"&(?:#[0-9]+|#[xX][0-9A-Fa-f]+|[A-Za-z][A-Za-z0-9]*);"#,
                options: .regularExpression
            ) == nil,
            "неподдержанная-сущность-в-локальном-адресе"
        )

        let декодированный = try декодировать(путь)
        try требоватьСсылки(
            !декодированный.hasPrefix("/")
                && декодированный.range(
                    of: #"^[A-Za-z][A-Za-z0-9+.-]*:"#,
                    options: .regularExpression
                ) == nil,
            "абсолютный-или-неоднозначный-адрес"
        )
        if декодированный.isEmpty {
            return Разбор(путь: документ, суффикс: суффикс)
        }

        var части = документ.split(separator: "/").dropLast().map(String.init)
        for часть in декодированный.split(
            separator: "/", omittingEmptySubsequences: false
        ) {
            if часть.isEmpty || часть == "." { continue }
            if часть == ".." {
                try требоватьСсылки(!части.isEmpty, "выход-за-корень")
                части.removeLast()
            } else {
                части.append(String(часть))
            }
        }
        return Разбор(путь: части.joined(separator: "/"), суффикс: суффикс)
    }

    static func закодировать(_ путь: String, угловое: Bool) -> String {
        let безопасные = Set(
            "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789/-._~!$&'*+,;=:@"
                .unicodeScalars
        )
        var итог = ""
        for знак in путь.unicodeScalars {
            if безопасные.contains(знак)
                || (знак.value >= 128 && !знак.properties.isWhitespace)
                || (угловое && знак.value == 32) {
                итог.unicodeScalars.append(знак)
            } else {
                for байт in String(знак).utf8 {
                    итог += String(format: "%%%02X", байт)
                }
            }
        }
        return итог
    }

    static func замена(
        _ адрес: Разбор,
        документ: String,
        пары: [ОтображениеПути],
        угловое: Bool
    ) throws -> String? {
        guard let путь = адрес.путь else { return nil }
        var назначение: String?
        var совпадения = 0
        for пара in пары {
            for (старый, кандидат) in [
                (true, пара.исходный), (false, пара.целевой)
            ] {
                guard ключ(путь) == ключ(кандидат) else { continue }
                try требоватьСсылки(
                    точно(путь, кандидат), "регистр-или-NFC-ссылки"
                )
                совпадения += 1
                if старый { назначение = пара.целевой }
            }
        }
        try требоватьСсылки(совпадения <= 1, "неоднозначная-пара")
        guard let назначение else { return nil }

        let родитель = документ.split(separator: "/").dropLast().map(String.init)
        let цель = назначение.split(separator: "/").map(String.init)
        var общий = 0
        while общий < родитель.count && общий < цель.count
            && точно(родитель[общий], цель[общий]) {
            общий += 1
        }
        let части = Array(repeating: "..", count: родитель.count - общий)
            + Array(цель.dropFirst(общий))
        return закодировать(части.joined(separator: "/"), угловое: угловое)
            + адрес.суффикс
    }
}

private struct ТокенСсылкиПакета {
    let целиком: Range<Int>
    let адрес: Range<Int>
    let угловое: Bool
    let меткаОпределения: String?
}

private final class СканерСсылокПакета {
    struct Строка {
        let начало: Int
        let телоКонец: Int
        let конец: Int
    }

    let байты: [UInt8]
    let путь: String
    let строки: [Строка]
    var скрыто: [Bool]
    var защищено: [Bool]
    var занято: [Bool]
    var неподдержано: [Bool]

    init(_ документ: ДокументСсылокПакета) throws {
        try требоватьСсылки(
            String(data: документ.байты, encoding: .utf8) != nil,
            "не-UTF8-Markdown"
        )
        путь = документ.путь
        байты = Array(документ.байты)
        скрыто = Array(repeating: false, count: байты.count)
        защищено = скрыто
        занято = скрыто
        неподдержано = скрыто
        var список: [Строка] = []
        var начало = 0
        for номер in байты.indices where байты[номер] == 10 {
            let конецТела = номер > начало && байты[номер - 1] == 13
                ? номер - 1 : номер
            список.append(.init(
                начало: начало, телоКонец: конецТела, конец: номер + 1
            ))
            начало = номер + 1
        }
        if начало < байты.count || список.isEmpty {
            список.append(.init(
                начало: начало, телоКонец: байты.count, конец: байты.count
            ))
        }
        строки = список
        try построитьМаски()
    }

    func текст(_ диапазон: Range<Int>) -> String {
        String(decoding: байты[диапазон], as: UTF8.self)
    }

    func отметить(_ диапазон: Range<Int>, _ маска: inout [Bool]) {
        for номер in диапазон { маска[номер] = true }
    }

    func экранирован(_ номер: Int) -> Bool {
        var курсор = номер
        var число = 0
        while курсор > 0 && байты[курсор - 1] == 92 {
            курсор -= 1
            число += 1
        }
        return число % 2 == 1
    }

    func видно(_ диапазон: Range<Int>) -> Bool {
        !диапазон.contains { скрыто[$0] }
    }

    func совпало(_ номер: Int, _ значение: String) -> Bool {
        let образец = Array(значение.utf8)
        return номер + образец.count <= байты.count
            && байты[номер..<(номер + образец.count)].elementsEqual(образец)
    }

    func пропуститьПробелы(_ начало: Int, перенос: Bool) -> Int {
        var курсор = начало
        while курсор < байты.count && [9, 32].contains(байты[курсор]) {
            курсор += 1
        }
        if перенос && курсор < байты.count {
            if байты[курсор] == 13 {
                курсор += 1
                if курсор < байты.count && байты[курсор] == 10 { курсор += 1 }
            } else if байты[курсор] == 10 {
                курсор += 1
            } else {
                return курсор
            }
            while курсор < байты.count && [9, 32].contains(байты[курсор]) {
                курсор += 1
            }
        }
        return курсор
    }

    func конецСтроки(_ начало: Int) -> (тело: Int, следующий: Int) {
        var номер = начало
        while номер < байты.count && байты[номер] != 10 { номер += 1 }
        let тело = номер > начало && байты[номер - 1] == 13 ? номер - 1 : номер
        return (тело, номер < байты.count ? номер + 1 : номер)
    }

    func закрытьМетку(_ начало: Int) -> Int? {
        var глубина = 1
        var курсор = начало + 1
        while курсор < байты.count {
            if скрыто[курсор] || [10, 13].contains(байты[курсор]) { return nil }
            if байты[курсор] == 92 && курсор + 1 < байты.count {
                курсор += 2
                continue
            }
            if байты[курсор] == 91 { глубина += 1 }
            if байты[курсор] == 93 {
                глубина -= 1
                if глубина == 0 { return курсор }
            }
            курсор += 1
        }
        return nil
    }

    func заголовок(_ начало: Int) -> Int? {
        guard начало < байты.count,
              [34, 39, 40].contains(байты[начало]) else { return nil }
        let открытие = байты[начало]
        let закрытие: UInt8 = открытие == 40 ? 41 : открытие
        var глубина = 1
        var курсор = начало + 1
        while курсор < байты.count {
            // Многострочный title здесь намеренно не принимается.
            if [10, 13].contains(байты[курсор]) { return nil }
            if байты[курсор] == 92 && курсор + 1 < байты.count {
                курсор += 2
                continue
            }
            if открытие == 40 && байты[курсор] == 40 { глубина += 1 }
            if байты[курсор] == закрытие {
                глубина -= 1
                if глубина == 0 { return курсор + 1 }
            }
            курсор += 1
        }
        return nil
    }

    func адрес(
        _ начало: Int, встроенный: Bool
    ) -> (диапазон: Range<Int>, угловое: Bool, конец: Int)? {
        guard начало < байты.count else { return nil }
        let угловое = байты[начало] == 60
        let началоАдреса = начало + (угловое ? 1 : 0)
        var курсор = началоАдреса
        var глубина = 0

        while курсор < байты.count {
            let знак = байты[курсор]
            if знак == 92 && курсор + 1 < байты.count {
                курсор += 2
                continue
            }
            if угловое {
                if знак == 62 {
                    return (началоАдреса..<курсор, true, курсор + 1)
                }
                if [10, 13, 60].contains(знак) { return nil }
            } else {
                if [9, 10, 13, 32].contains(знак) {
                    return глубина == 0
                        ? (началоАдреса..<курсор, false, курсор) : nil
                }
                if знак == 40 { глубина += 1 }
                if знак == 41 {
                    if глубина == 0 {
                        return встроенный
                            ? (началоАдреса..<курсор, false, курсор) : nil
                    }
                    глубина -= 1
                }
            }
            курсор += 1
        }
        return !угловое && глубина == 0
            ? (началоАдреса..<курсор, false, курсор) : nil
    }

    func встроенная(_ начало: Int, скобка: Int) -> ТокенСсылкиПакета? {
        let началоАдреса = пропуститьПробелы(скобка + 1, перенос: true)
        guard let разбор = адрес(началоАдреса, встроенный: true) else {
            return nil
        }
        var курсор = разбор.конец
        let разделитель = курсор
        курсор = пропуститьПробелы(курсор, перенос: true)
        if курсор < байты.count && байты[курсор] != 41 {
            guard курсор > разделитель, let конец = заголовок(курсор) else {
                return nil
            }
            курсор = пропуститьПробелы(конец, перенос: true)
        }
        guard курсор < байты.count, байты[курсор] == 41,
              видно(начало..<(курсор + 1)) else { return nil }
        return .init(
            целиком: начало..<(курсор + 1),
            адрес: разбор.диапазон,
            угловое: разбор.угловое,
            меткаОпределения: nil
        )
    }

    func ключМетки(_ значение: String) -> String {
        АдресСсылкиПакета.ключ(
            АдресСсылкиПакета.снятьЭкранирование(значение)
                .split(whereSeparator: \.isWhitespace)
                .joined(separator: " ")
        )
    }

    func определение(_ строка: Строка) -> ТокенСсылкиПакета? {
        var начало = строка.начало
        var отступ = 0
        while начало < строка.телоКонец && байты[начало] == 32 && отступ < 3 {
            начало += 1
            отступ += 1
        }
        guard начало < строка.телоКонец, байты[начало] == 91,
              let закрытие = закрытьМетку(начало),
              закрытие + 1 < строка.телоКонец,
              байты[закрытие + 1] == 58 else { return nil }

        let началоАдреса = пропуститьПробелы(закрытие + 2, перенос: true)
        guard let разбор = адрес(началоАдреса, встроенный: false),
              !разбор.диапазон.isEmpty else { return nil }
        var курсор = пропуститьПробелы(разбор.конец, перенос: false)
        var предел = конецСтроки(курсор)

        if курсор == предел.тело && предел.следующий < байты.count {
            let следующий = пропуститьПробелы(предел.следующий, перенос: false)
            if следующий < байты.count && [34, 39, 40].contains(байты[следующий]) {
                курсор = следующий
                предел = конецСтроки(курсор)
            }
        }
        if курсор < предел.тело {
            guard let конец = заголовок(курсор) else { return nil }
            курсор = пропуститьПробелы(конец, перенос: false)
        }
        guard курсор == предел.тело,
              видно(начало..<курсор) else { return nil }
        return .init(
            целиком: начало..<предел.следующий,
            адрес: разбор.диапазон,
            угловое: разбор.угловое,
            меткаОпределения: ключМетки(текст((начало + 1)..<закрытие))
        )
    }

    func построитьМаски() throws {
        var комментарий = false
        var ограда: (знак: UInt8, длина: Int)?
        var передняяЧасть = false

        if let первая = строки.first, текст(первая.начало..<первая.телоКонец) == "+++" {
            передняяЧасть = true
        }

        for (номерСтроки, строка) in строки.enumerated() {
            let весь = строка.начало..<строка.конец
            let тело = текст(строка.начало..<строка.телоКонец)
            if передняяЧасть {
                отметить(весь, &скрыто)
                if номерСтроки > 0 && тело == "+++" { передняяЧасть = false }
                continue
            }

            var начало = строка.начало
            while начало < строка.телоКонец
                && байты[начало] == 32
                && начало - строка.начало < 3 {
                начало += 1
            }

            if let текущая = ограда {
                отметить(весь, &скрыто)
                var конец = начало
                while конец < строка.телоКонец
                    && байты[конец] == текущая.знак { конец += 1 }
                if конец - начало >= текущая.длина,
                   байты[конец..<строка.телоКонец].allSatisfy({
                       $0 == 9 || $0 == 32
                   }) {
                    ограда = nil
                }
                continue
            }

            // Не угадываем вложенность list/blockquote continuation.
            if тело.hasPrefix("    ") || тело.hasPrefix("\t") || тело.trimmingCharacters(in: .whitespaces).hasPrefix(">") {
                отметить(весь, &неподдержано)
            }

            if !комментарий, начало < строка.телоКонец, !скрыто[начало],
               [96, 126].contains(байты[начало]) {
                var конец = начало
                while конец < строка.телоКонец
                    && байты[конец] == байты[начало] { конец += 1 }
                if конец - начало >= 3 && (байты[начало] != 96 || !байты[конец..<строка.телоКонец].contains(96)) {
                    ограда = (байты[начало], конец - начало)
                    отметить(весь, &скрыто)
                    continue
                }
            }

            var курсор = строка.начало
            while курсор < строка.телоКонец {
                if скрыто[курсор] { курсор += 1; continue }
                if комментарий {
                    скрыто[курсор] = true
                    if совпало(курсор, "-->") {
                        отметить(курсор..<(курсор + 3), &скрыто)
                        курсор += 3
                        комментарий = false
                    } else {
                        курсор += 1
                    }
                    continue
                }
                if совпало(курсор, "<!--") {
                    отметить(курсор..<(курсор + 4), &скрыто)
                    курсор += 4
                    комментарий = true
                    continue
                }
                if байты[курсор] == 96 && !экранирован(курсор) {
                    var конецОткрытия = курсор
                    while конецОткрытия < строка.телоКонец
                        && байты[конецОткрытия] == 96 { конецОткрытия += 1 }
                    let длина = конецОткрытия - курсор
                    var предел = байты.count
                    for следующая in строки where следующая.начало >= строка.конец {
                        let телоСледующей = текст(следующая.начало..<следующая.телоКонец)
                        if телоСледующей.trimmingCharacters(in: .whitespaces).isEmpty
                            || телоСледующей.range(of: #"^[ ]{0,3}(?:#{1,6}(?:[ \t]|$)|>|[-+*][ \t]|[0-9]{1,9}[.)][ \t]|`{3}|~{3}|(?:=+|-+)[ \t]*$)"#, options: .regularExpression) != nil {
                            предел = следующая.начало; break
                        }
                    }
                    var поиск = конецОткрытия
                    var закрытие: Int?
                    while поиск < предел {
                        if байты[поиск] != 96 { поиск += 1; continue }
                        var конец = поиск
                        while конец < предел && байты[конец] == 96 {
                            конец += 1
                        }
                        if конец - поиск == длина { закрытие = конец; break }
                        поиск = конец
                    }
                    guard let закрытие else {
                        отметить(весь, &неподдержано)
                        курсор = конецОткрытия
                        continue
                    }
                    отметить(курсор..<закрытие, &скрыто)
                    курсор = закрытие
                    continue
                }
                курсор += 1
            }
        }
        try требоватьСсылки(!передняяЧасть, "незамкнутая-передняя-часть")

        if путь.hasPrefix("Источники/") {
            защищено = Array(repeating: true, count: байты.count)
            return
        }

        var разделы: [(строка: Строка, название: String)] = []
        for строка in строки {
            let диапазон = строка.начало..<строка.телоКонец
            guard видно(диапазон) else { continue }
            let видимое = текст(диапазон)
            guard видимое.range(
                of: #"^[ ]{0,3}##[ \t]+"#,
                options: .regularExpression
            ) != nil else { continue }
            let название = видимое
                .replacingOccurrences(
                    of: #"^[ ]{0,3}##[ \t]+"#,
                    with: "", options: .regularExpression
                )
                .replacingOccurrences(
                    of: #"[ \t]+#+[ \t]*$"#,
                    with: "", options: .regularExpression
                )
                .trimmingCharacters(in: .whitespaces)
            разделы.append((строка, название))
        }
        let запрос = путь.hasPrefix("Журнал/")
            && (путь as NSString).lastPathComponent == "запрос.md"
        let число = разделы.filter { $0.название == "Текст запроса" }.count
        if запрос && число != 1 {
            // Не классифицируем неизвестную старую форму как производную.
            защищено = Array(repeating: true, count: байты.count)
            return
        }
        for номер in разделы.indices
            where разделы[номер].название == "Текст запроса" {
            let конец = номер + 1 < разделы.count
                ? разделы[номер + 1].строка.начало : байты.count
            отметить(разделы[номер].строка.конец..<конец, &защищено)
        }
    }
}

enum РешательСсылокПакета {
    static func обновитьСвежесть(_ данные: Data, путь: String, время: String) throws -> Data {
        guard let текст = String(data: данные, encoding: .utf8) else { throw ОтказСсылокПакета.условие("не-UTF8-recency") }
        let сканер = try СканерСсылокПакета(ДокументСсылокПакета(путь: путь, байты: данные, sha256: хэшПутей(данные)))
        let шаблон = #"(?:\A|\r?\n)<!-- FUM-MD-RECENCY:BEGIN -->\r?\n<!-- last-content-edit: ([^>]+) -->\r?\n<!-- content-sha256: sha256:([0-9a-f]{64}) -->\r?\n<!-- FUM-MD-RECENCY:END -->\r?\n?\z"#
        let выражение = try NSRegularExpression(pattern: шаблон)
        let совпадение = выражение.firstMatch(in: текст, range: NSRange(текст.startIndex..., in: текст))
        var содержимое = текст
        if let совпадение, let диапазон = Range(совпадение.range, in: текст) {
            let начало = текст[..<диапазон.lowerBound].utf8.count
            guard !сканер.скрыто.dropFirst(начало).allSatisfy({ $0 }) else {
                throw ОтказСсылокПакета.условие("метка-recency-в-ограде")
            }
            содержимое = String(текст[..<диапазон.lowerBound])
        } else {
            let видимые = сканер.байты.indices.map { сканер.скрыто[$0] ? UInt8(32) : сканер.байты[$0] }
            let видимыйТекст = String(decoding: видимые, as: UTF8.self)
            if видимыйТекст.contains("FUM-MD-RECENCY:BEGIN") || видимыйТекст.contains("FUM-MD-RECENCY:END") {
                throw ОтказСсылокПакета.условие("повреждённая-recency")
            }
        }
        if !содержимое.hasSuffix("\n") { содержимое += "\n" }
        var дляХэша = содержимое.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        let части = путь.split(separator: "/")
        if части.count == 3, части[0] == "Журнал", части[2] == "отчёт.md" {
            let начал = дляХэша.components(separatedBy: "<!-- FUM-CHECK-RUNS:BEGIN ").count - 1
            let концов = дляХэша.components(separatedBy: "<!-- FUM-CHECK-RUNS:END -->").count - 1
            if начал != 0 || концов != 0 {
                let шаблонЗапусков = #"(?ms)^<!-- FUM-CHECK-RUNS:BEGIN (?:состояние=открыт; каталог=материалы/запуски-проверок|состояние=закрыт; снимок=материалы/запуски-проверок/снимок\.json; sha256=sha256:[0-9a-f]{64}) -->\n.*?\n<!-- FUM-CHECK-RUNS:END -->$"#
                let выражениеЗапусков = try NSRegularExpression(pattern: шаблонЗапусков)
                let найденные = выражениеЗапусков.matches(in: дляХэша, range: NSRange(дляХэша.startIndex..., in: дляХэша))
                guard начал == 1, концов == 1, найденные.count == 1, let диапазон = Range(найденные[0].range, in: дляХэша) else {
                    throw ОтказСсылокПакета.условие("повреждённый-блок-проверок-recency")
                }
                дляХэша.replaceSubrange(диапазон, with: "<!-- FUM-CHECK-RUNS:MANAGED -->")
            }
        }
        let хэш = хэшПутей(Data(дляХэша.utf8))
        return Data((содержимое + "\n<!-- FUM-MD-RECENCY:BEGIN -->\n<!-- last-content-edit: \(время) -->\n<!-- content-sha256: sha256:\(хэш) -->\n<!-- FUM-MD-RECENCY:END -->\n").utf8)
    }

    // Это консервативный detector для неподдержанных конструкций,
    // а не дополнительный способ разрешения адреса.
    private static func похожеНаПакет(
        _ значение: String, пары: [ОтображениеПути]
    ) -> Bool {
        let снятое = АдресСсылкиПакета.снятьЭкранирование(значение)
        let варианты = [значение, снятое, снятое.removingPercentEncoding ?? снятое]
            .map(АдресСсылкиПакета.ключ)
        let имена = пары.flatMap { [$0.исходный, $0.целевой] }.flatMap {
            let имя = ($0 as NSString).lastPathComponent
            return [имя, (имя as NSString).deletingPathExtension]
        }.map(АдресСсылкиПакета.ключ)
        return варианты.contains { вариант in
            имена.contains { !($0.isEmpty) && вариант.contains($0) }
        }
    }

    static func разрешить(
        документы: [ДокументСсылокПакета],
        ожидаемыеПути: [String],
        пары: [ОтображениеПути],
        разрешённыеДокументы: Set<String>,
        проверитьАдрес: (String) throws -> Void
    ) throws -> [ИзменениеСсылокПакета] {
        try требоватьСсылки(пары.count == 9, "нужны-девять-пар")
        let упорядоченные = документы.sorted {
            порядокПутей($0.путь, $1.путь)
        }
        let фактические = упорядоченные.map(\.путь)
        let ожидаемые = ожидаемыеПути.sorted(by: порядокПутей)
        try требоватьСсылки(
            фактические.map { Data($0.utf8) }
                == ожидаемые.map { Data($0.utf8) }
                && Set(фактические.map { Data($0.utf8) }).count
                    == фактические.count,
            "неполный-или-повторный-Markdown-инвентарь"
        )

        var результаты: [ИзменениеСсылокПакета] = []

        // Один общий проход по переданному полному inventory для всех девяти пар.
        for документ in упорядоченные {
            try требоватьСсылки(
                хэшПутей(документ.байты) == документ.sha256,
                "дрейф-байтов-Markdown"
            )
            let сканер = try СканерСсылокПакета(документ)
            var токены: [ТокенСсылкиПакета] = []
            var определения: [String: [ТокенСсылкиПакета]] = [:]
            var защищённыеМетки: Set<String> = []

            for строка in сканер.строки {
                guard let токен = сканер.определение(строка) else { continue }
                токены.append(токен)
                определения[токен.меткаОпределения!, default: []].append(токен)
                сканер.отметить(токен.целиком, &сканер.занято)
            }

            for группа in определения.values where группа.count > 1 {
                if группа.contains(where: {
                    похожеНаПакет(сканер.текст($0.адрес), пары: пары)
                }) {
                    throw ОтказСсылокПакета.условие(
                        "повторное-относящееся-reference-определение"
                    )
                }
            }

            var курсор = 0
            while курсор < сканер.байты.count {
                if сканер.скрыто[курсор] || сканер.занято[курсор] {
                    курсор += 1
                    continue
                }
                if сканер.совпало(курсор, "[[")
                    && !сканер.экранирован(курсор) {
                    let предел = сканер.конецСтроки(курсор).тело
                    var конец = курсор + 2
                    while конец < предел && !сканер.совпало(конец, "]]") {
                        конец += 1
                    }
                    let цель = сканер.текст((курсор + 2)..<конец)
                        .components(separatedBy: "|")[0]
                        .components(separatedBy: "#")[0]
                    try требоватьСсылки(
                        !похожеНаПакет(цель, пары: пары),
                        "относящийся-wikilink"
                    )
                    курсор = конец < предел ? конец + 2 : предел
                    continue
                }

                let изображение = сканер.байты[курсор] == 33
                    && курсор + 1 < сканер.байты.count
                    && сканер.байты[курсор + 1] == 91
                let открытие = курсор + (изображение ? 1 : 0)
                if открытие < сканер.байты.count,
                   сканер.байты[открытие] == 91,
                   !сканер.экранирован(открытие),
                   let закрытие = сканер.закрытьМетку(открытие) {
                    if закрытие + 1 < сканер.байты.count,
                       сканер.байты[закрытие + 1] == 40,
                       let токен = сканер.встроенная(
                           курсор, скобка: закрытие + 1
                       ) {
                        токены.append(токен)
                        сканер.отметить(токен.целиком, &сканер.занято)
                        курсор = токен.целиком.upperBound
                        continue
                    }

                    var ключ = сканер.ключМетки(
                        сканер.текст((открытие + 1)..<закрытие)
                    )
                    var конец = закрытие + 1
                    if конец < сканер.байты.count,
                       сканер.байты[конец] == 91,
                       let правый = сканер.закрытьМетку(конец) {
                        if правый > конец + 1 {
                            ключ = сканер.ключМетки(
                                сканер.текст((конец + 1)..<правый)
                            )
                        }
                        конец = правый + 1
                    }
                    if определения[ключ] != nil {
                        if (курсор..<конец).contains(where: { сканер.защищено[$0] }) { защищённыеМетки.insert(ключ) }
                        сканер.отметить(курсор..<конец, &сканер.занято)
                        курсор = конец
                        continue
                    }
                }
                курсор += 1
            }

            // Неразобранная относящаяся конструкция никогда не становится нулём.
            for строка in сканер.строки {
                let остаток = строка.начало..<строка.телоКонец
                let видимые = остаток.map { номер -> UInt8 in
                    сканер.скрыто[номер] || сканер.занято[номер]
                        ? 32 : сканер.байты[номер]
                }
                let текст = String(decoding: видимые, as: UTF8.self)
                let синтаксис = текст.contains("[") || текст.contains("<")
                    || текст.range(
                        of: #"(?i)\b(?:href|src)[ \t]*="#,
                        options: .regularExpression
                    ) != nil
                if синтаксис && (
                    похожеНаПакет(текст, пары: пары)
                        || текст.contains("&#")
                ) {
                    throw ОтказСсылокПакета.условие(
                        "относящийся-неподдержанный-Markdown"
                    )
                }
            }

            let остаточныеБайты = сканер.байты.indices.map { номер -> UInt8 in
                сканер.скрыто[номер] || сканер.занято[номер] ? 32 : сканер.байты[номер]
            }
            for абзац in String(decoding: остаточныеБайты, as: UTF8.self).components(separatedBy: "\n\n") {
                if абзац.contains("<"), абзац.range(of: #"(?i)\b(?:href|src)\s*="#, options: .regularExpression) != nil,
                   абзац.range(of: #"&(?:#[0-9]+|#[xX][0-9A-Fa-f]+|[A-Za-z][A-Za-z0-9]*);"#, options: .regularExpression) != nil {
                    throw ОтказСсылокПакета.условие("неподдержанные-HTML-entities-адреса")
                }
                if (абзац.contains("[") || абзац.contains("<")) && похожеНаПакет(абзац, пары: пары) {
                    throw ОтказСсылокПакета.условие("относящийся-многострочный-остаток")
                }
            }

            var правки: [ПравкаСсылкиПакета] = []
            for токен in токены.sorted(by: {
                $0.адрес.lowerBound < $1.адрес.lowerBound
            }) {
                let сырой = сканер.текст(токен.адрес)
                let адрес = try АдресСсылкиПакета.разобрать(
                    сырой, документ: документ.путь
                )
                if let путь = адрес.путь { try проверитьАдрес(путь) }
                guard let новый = try АдресСсылкиПакета.замена(
                    адрес, документ: документ.путь,
                    пары: пары, угловое: токен.угловое
                ) else { continue }

                if let метка = токен.меткаОпределения, защищённыеМетки.contains(метка) {
                    throw ОтказСсылокПакета.условие("definition-меняет-дословную-ссылку")
                }

                try требоватьСсылки(
                    !токен.целиком.contains { сканер.неподдержано[$0] },
                    "относящийся-неподдержанный-container"
                )
                try требоватьСсылки(
                    !токен.целиком.contains { сканер.защищено[$0] },
                    "ссылка-в-дословной-области"
                )
                try требоватьСсылки(
                    разрешённыеДокументы.contains(документ.путь),
                    "новый-неразрешённый-документ-ссылки"
                )
                правки.append(.init(
                    диапазон: токен.адрес,
                    прежние: документ.байты.subdata(in: токен.адрес),
                    новые: Data(новый.utf8)
                ))
            }

            for номер in правки.indices where номер > 0 {
                try требоватьСсылки(
                    правки[номер - 1].диапазон.upperBound
                        <= правки[номер].диапазон.lowerBound,
                    "пересекающиеся-правки"
                )
            }
            if правки.isEmpty { continue }
            var будущие = Data(документ.байты)
            for правка in правки.reversed() {
                будущие.replaceSubrange(правка.диапазон, with: правка.новые)
            }
            результаты.append(.init(
                путь: документ.путь,
                исходныйХэш: документ.sha256,
                правки: правки,
                будущиеБайты: будущие
            ))
        }
        return результаты
    }
}

import Foundation

// Адресный Source-профиль P4. Отображается только первый компонент пути;
// Names/LK не вызывается. Legacy fixed9 и общий CLI этим файлом не меняются.
struct КаноническаяКопияДокументации: Codable, Equatable, Sendable {
    var исходный: String
    var целевой: String
    var исходныйSHA256: String
    var целевойSHA256: String
    var основание: String
    var подготовленнаяЦель = false
}

struct РешениеСлиянияREADMEДокументации: Codable, Equatable, Sendable {
    var исходныйSHA256: String
    var целевойSHA256: String
    var основание: String
    var подготовленнаяЦель = false
}

enum ДействиеПакетаДокументации: String, Codable, Sendable {
    case создатьКаталог, перенестиФайл, заменитьБайты, схлопнутьКопию, удалитьПустойКаталог
}

struct ОжиданиеУзлаДокументации: Codable, Equatable, Sendable {
    var путь: String
    var вид: String
    var режим: String?
    var sha256: String?
}

struct ШагПакетаДокументации: Codable, Equatable, Sendable {
    var номер: Int
    var действие: ДействиеПакетаДокументации
    var исходный: String?
    var целевой: String
    var до: [ОжиданиеУзлаДокументации]
    var после: [ОжиданиеУзлаДокументации]
    var байтыПосле: Data?
}

struct ПравкаДляВладельцаДокументации: Codable, Equatable, Sendable {
    var путь: String
    var исходныйSHA256: String
    var будущиеБайты: Data
    var будущийSHA256: String
    var действиеВладельца = "согласовать адресную правку до отдельного решения об исполнении"
}

struct ВходящийДокументПакетаДокументации: Codable, Equatable, Sendable {
    var путь: String
    var байты: Data
    var sha256: String
}

struct ПланПакетаДокументации: Codable, Equatable, Sendable {
    var схема = "fum.профиль-объединения-документации.1"
    var источникОтображения = "явное поручение ROOT-P4-AUTOMATED-DOCS-MERGE-CONTINUE-01; хвосты сохранены"
    var основа: ОсноваОбщейМиграции
    var исходныеУзлы: [УзелОбщейМиграции]
    var индексДо: Data
    var исходноеПространство: [Data]
    var конечноеПространство: [Data]
    var отображения: [СтрокаОбщегоОтображения]
    var каноны: [КаноническаяКопияДокументации]
    var слияниеREADME: РешениеСлиянияREADMEДокументации?
    var входящиеДо: [ВходящийДокументПакетаДокументации]
    var времяСвежести: String?
    var нормализованные: [String: РазрешённыйДокументМиграции]
    var шаги: [ШагПакетаДокументации]
    var внешниеПравки: [ПравкаДляВладельцаДокументации]
    var препятствия: [ПрепятствиеОбщейМиграции]
    var прочиеВходящие = "UNKNOWN; отдельный список и владельцы обязательны перед исполнением"
    var системныйАдаптер = "UNKNOWN; concrete journal/file adapter не подключён этим Source"
}

enum ПрофильОбъединенияДокументации {
    private static let верх = "Документация"
    private static let низ = "dokumentaciya"

    private static func относится(_ путь: String, к корню: String) -> Bool {
        Data(путь.utf8) == Data(корню.utf8) || Data(путь.utf8).starts(with: Data((корню + "/").utf8))
    }

    static func назначение(_ путь: String) -> String {
        относится(путь, к: верх) ? низ + String(decoding: путь.utf8.dropFirst(верх.utf8.count), as: UTF8.self) : путь
    }

    static func построить(основа: ОсноваОбщейМиграции, ожидаемаяОснова: ОсноваОбщейМиграции,
        узлы: [УзелОбщейМиграции], пространство: Set<Data>, индексДо: Data,
        каноны: [КаноническаяКопияДокументации] = [],
        входящие: [ДокументСсылокПакета] = [], времяСвежести: String? = nil,
        слияниеREADME: РешениеСлиянияREADMEДокументации? = nil) throws -> ПланПакетаДокументации {
        guard !узлы.isEmpty, узлы.count <= 8192, входящие.count <= 8192,
              индексДо.count <= 67_108_864, хэшПутей(индексДо) == основа.индексSHA256 else {
            throw ОтказОбщейМиграции.условие("неверный-состав-или-индекс-профиля-Docs")
        }
        if let времяСвежести {
            let формат = DateFormatter(); формат.locale = Locale(identifier: "en_US_POSIX")
            формат.timeZone = TimeZone(identifier: "Europe/Moscow"); формат.isLenient = false
            формат.dateFormat = "yyyy-MM-dd HH:mm:ss 'MSK'"
            guard времяСвежести.utf8.count == 23,
                  формат.date(from: времяСвежести).map({ формат.string(from: $0) == времяСвежести }) == true else {
                throw ОтказОбщейМиграции.условие("неверное-явное-время-свежести-Docs")
            }
        }
        var объём = 0
        for байты in узлы.map(\.байты) + входящие.map(\.байты) {
            guard байты.count <= 8_388_608, байты.count <= 134_217_728 - объём else {
                throw ОтказОбщейМиграции.условие("предел-байтов-профиля-Docs")
            }
            объём += байты.count
        }
        // Повторно используем структурные проверки общего планировщика без его
        // LK-контракта корневого имени: здесь имя уже задано человеком.
        let исходныйПлан = try ОбщийПланировщикПутей.построить(основа: основа, ожидаемаяОснова: ожидаемаяОснова,
            узлы: узлы, корни: [])
        var препятствия = исходныйПлан.препятствия.filter { $0.код != "не-проверены-ссылки" }
        guard препятствия.isEmpty else { throw ОтказОбщейМиграции.условие("небезопасный-исходный-состав-Docs") }
        guard узлы.allSatisfy({ относится($0.путь, к: верх) || относится($0.путь, к: низ) }),
              !узлы.contains(where: { относится($0.путь, к: верх) }) || узлы.contains(where: { Data($0.путь.utf8) == Data(верх.utf8) && $0.вид == .каталог }),
              Set(узлы.map { Data($0.путь.utf8) }) == Set(пространство.filter {
                  let путь = String(decoding: $0, as: UTF8.self)
                  return относится(путь, к: верх) || относится(путь, к: низ)
              }) else {
            throw ОтказОбщейМиграции.условие("узел-вне-двух-каталогов-Docs")
        }
        let конечное = Set(пространство.map { Data(назначение(String(decoding: $0, as: UTF8.self)).utf8) })
        for выбранное in [пространство, конечное] {
          var алиасы: [Data: Data] = [:]
          for ключ in выбранное {
            guard let путь = String(data: ключ, encoding: .utf8) else { throw ОтказОбщейМиграции.условие("не-UTF8-пространство-Docs") }
            try ИменаПутей.проверитьПуть(путь)
            var префикс = ""
            for часть in ИменаПутей.компоненты(путь) {
                префикс += (префикс.isEmpty ? "" : "/") + часть
                let алиас = ИменаПутей.ключКоллизии(префикс), точный = Data(префикс.utf8)
                if let прежний = алиасы[алиас], прежний != точный { throw ОтказОбщейМиграции.условие("алиасы-пространства-Docs") }
                алиасы[алиас] = точный
            }
          }
        }
        let поПути = Dictionary(uniqueKeysWithValues: узлы.map { (Data($0.путь.utf8), $0) })
        if let слияниеREADME {
            guard let исходный = поПути[Data("Документация/README.md".utf8)],
                  let целевой = поПути[Data("dokumentaciya/README.md".utf8)],
                  исходный.вид == .файл, целевой.вид == .файл, !исходный.дословный, !целевой.дословный,
                  исходный.режим == целевой.режим, !слияниеREADME.основание.isEmpty,
                  !целевой.объект.isEmpty || слияниеREADME.подготовленнаяЦель,
                  хэшПутей(исходный.байты) == слияниеREADME.исходныйSHA256,
                  хэшПутей(целевой.байты) == слияниеREADME.целевойSHA256,
                  времяСвежести != nil else { throw ОтказОбщейМиграции.условие("не-подтверждено-слияние-README-Docs") }
        }
        let упорядоченные = узлы.sorted { порядокПутей($0.путь, $1.путь) }
        let отображения = упорядоченные.map { СтрокаОбщегоОтображения(исходный: $0.путь, целевой: назначение($0.путь)) }
        var разрешения: [Data: КаноническаяКопияДокументации] = [:]
        for канон in каноны {
            guard let исходный = поПути[Data(канон.исходный.utf8)], let целевой = поПути[Data(канон.целевой.utf8)],
                  относится(исходный.путь, к: верх), Data(назначение(исходный.путь).utf8) == Data(целевой.путь.utf8),
                  исходный.вид == .файл, целевой.вид == .файл, !канон.основание.isEmpty,
                  !целевой.объект.isEmpty || канон.подготовленнаяЦель,
                  хэшПутей(исходный.байты) == канон.исходныйSHA256, хэшПутей(целевой.байты) == канон.целевойSHA256,
                  разрешения.updateValue(канон, forKey: Data(канон.исходный.utf8)) == nil else {
                throw ОтказОбщейМиграции.условие("дрейф-или-повтор-решения-канона-Docs")
            }
        }
        let документы = упорядоченные.filter { $0.вид == .файл && ($0.путь as NSString).pathExtension.lowercased() == "md" }
            .map { ДокументСсылокПакета(путь: $0.путь, байты: $0.байты, sha256: хэшПутей($0.байты)) }
        guard входящие.allSatisfy({ !относится($0.путь, к: верх) && !относится($0.путь, к: низ) }) else {
            throw ОтказОбщейМиграции.условие("входящий-документ-дублирует-Docs")
        }
        let весьКорпус = документы + входящие
        var нормализованные = try РешательСсылокПакета.разрешитьМиграцию(документы: весьКорпус,
            ожидаемыеПути: весьКорпус.map(\.путь), отображения: отображения,
            исходныеПути: пространство, конечныеПути: конечное,
            дословныеДокументы: Set(узлы.filter(\.дословный).map { Data($0.путь.utf8) }))
        let группы = Dictionary(grouping: упорядоченные, by: { Data(назначение($0.путь).utf8) })
        for узел in узлы where узел.дословный && (узел.путь as NSString).pathExtension.lowercased() == "md" {
            if относится(узел.путь, к: верх) || (группы[Data(назначение(узел.путь).utf8)]?.count ?? 0) > 1 {
                препятствия.append(.init(код: "дословный-Markdown-требует-отдельной-проверки", пути: [узел.путь]))
            }
        }
        for документ in весьКорпус {
            guard var итог = нормализованные[документ.путь] else { throw ОтказОбщейМиграции.условие("неполный-результат-решателя-Docs") }
            let группа = группы[Data(назначение(документ.путь).utf8)] ?? []
            let нужнаНормализацияКопий = группа.count > 1 && (Set(группа.map { хэшПутей($0.байты) }).count > 1
                || назначение(документ.путь) == "dokumentaciya/README.md" && слияниеREADME != nil)
            if итог.байтыПосле != документ.байты || нужнаНормализацияКопий {
                итог.байтыПосле = try обновитьСвежесть(итог.байтыПосле, путь: назначение(документ.путь), время: времяСвежести)
                нормализованные[документ.путь] = итог
            }
        }
        if слияниеREADME != nil {
            // Якорная неоднозначность относится также к входящим ссылкам.
            // При известной цели README и любом fragment в том же документе
            // выбираем безопасный отказ; точный token→anchor adapter ещё не дан.
            for документ in весьКорпус where нормализованные[документ.путь]?.целиПосле.contains("dokumentaciya/README.md") == true {
                let перечень = РешательСсылокПакета.перечислитьАдреса(документ)
                guard перечень.обходЗавершён, перечень.синтаксисПолностьюРаспознан, перечень.ошибки.isEmpty else {
                    throw ОтказОбщейМиграции.условие("не-проверен-входящий-README-корпус")
                }
                for узел in перечень.узлы {
                    if let адрес = узел.адрес, документ.байты.subdata(in: адрес).contains(35) {
                        throw ОтказОбщейМиграции.условие("нужен-адаптер-входящих-якорей-README")
                    }
                }
            }
        }
        func будущиеБайты(_ узел: УзелОбщейМиграции) -> Data { нормализованные[узел.путь]?.байтыПосле ?? узел.байты }
        func цели(_ узел: УзелОбщейМиграции) -> [Data] { (нормализованные[узел.путь]?.целиПосле ?? []).map { Data($0.utf8) } }
        var будущийОбъём = 0
        for результат in нормализованные.values {
            guard результат.байтыПосле.count <= 134_217_728 - будущийОбъём else {
                throw ОтказОбщейМиграции.условие("предел-будущих-байтов-Docs")
            }
            будущийОбъём += результат.байтыПосле.count
        }
        var будущиеУзлы: [УзелОбщейМиграции] = []
        for ключ in группы.keys.sorted(by: { $0.lexicographicallyPrecedes($1) }) {
            let члены = группы[ключ]!
            let имя = String(decoding: ключ, as: UTF8.self)
            let исходные = члены.map(\.путь)
            if члены.contains(where: { $0.вид == .ссылка || $0.вид == .внешняяГраница }) {
                препятствия.append(.init(код: "не-обычный-узел-Docs", пути: исходные)); continue
            }
            if члены.allSatisfy({ $0.вид == .каталог }) {
                будущиеУзлы.append(.init(путь: имя, вид: .каталог, режим: "040000")); continue
            }
            guard члены.allSatisfy({ $0.вид == .файл }) else {
                препятствия.append(.init(код: "несовместимые-типы-Docs", пути: исходные)); continue
            }
            let канонический = члены.first(where: { Data($0.путь.utf8) == ключ }) ?? члены[0]
            let объединитьREADME = имя == "dokumentaciya/README.md" && слияниеREADME != nil
            if члены.count > 1 {
                for член in члены where Data(член.путь.utf8) != ключ {
                    if разрешения[Data(член.путь.utf8)] == nil && !объединитьREADME {
                        препятствия.append(.init(код: "занятая-цель-без-решения", пути: [член.путь, имя]))
                    }
                }
                if !объединитьREADME && члены.contains(where: { $0.режим != канонический.режим || будущиеБайты($0) != будущиеБайты(канонический) || цели($0) != цели(канонический) }) {
                    препятствия.append(.init(код: "разные-нормализованные-листья", пути: исходные))
                }
            }
            var итог = канонический; итог.путь = имя; итог.байты = будущиеБайты(канонический)
            if объединитьREADME {
                guard let исходный = члены.first(where: { $0.путь == "Документация/README.md" }), let времяСвежести else {
                    throw ОтказОбщейМиграции.условие("неполная-пара-README-Docs")
                }
                // Конечное адресное слияние: сохраняем оба нормализованных тела
                // целиком, включая их источники. Произвольного winning payload нет.
                let верхнееТело = try телоREADME(будущиеБайты(исходный))
                let нижнееТело = try телоREADME(будущиеБайты(канонический))
                let составное = Data((нижнееТело + "\n\n## Полная тематическая карта\n\n" + верхнееТело + "\n").utf8)
                итог.байты = try РешательСсылокПакета.обновитьСвежесть(составное, путь: имя, время: времяСвежести)
                guard итог.байты.count <= 8_388_608 else { throw ОтказОбщейМиграции.условие("предел-составного-README-Docs") }
                let документ = ДокументСсылокПакета(путь: имя, байты: итог.байты, sha256: хэшПутей(итог.байты))
                let перечень = РешательСсылокПакета.перечислитьАдреса(документ)
                guard перечень.обходЗавершён, перечень.синтаксисПолностьюРаспознан, перечень.ошибки.isEmpty else {
                    throw ОтказОбщейМиграции.условие("неоднозначные-ссылки-составного-README")
                }
                // Якоря при склейке меняют пространство имён заголовков.
                // До отдельного anchor-adapter этот конечный профиль закрыто
                // отклоняет fragment-адреса, включая внешние: не угадывает slug.
                for узел in перечень.узлы {
                    if let адрес = узел.адрес, итог.байты.subdata(in: адрес).contains(35) {
                        throw ОтказОбщейМиграции.условие("нужен-адаптер-якорей-составного-README")
                    }
                }
                let сверка = try РешательСсылокПакета.разрешитьМиграцию(документы: [документ], ожидаемыеПути: [имя],
                    отображения: [], исходныеПути: конечное, конечныеПути: конечное)
                guard let проверенный = сверка[имя], проверенный.байтыПосле == итог.байты,
                      проверенный.целиПосле.map({ Data($0.utf8) }) == цели(канонический) + цели(исходный) else {
                    throw ОтказОбщейМиграции.условие("изменились-цели-составного-README")
                }
                нормализованные[имя] = проверенный
            }
            будущиеУзлы.append(итог)
        }
        // Тот же общий валидатор проверяет собранное конечное пространство:
        // файловые префиксы, типы, Unicode/case aliases и точные режимы.
        let будущаяСтруктура = try ОбщийПланировщикПутей.построить(основа: основа, ожидаемаяОснова: ожидаемаяОснова,
            узлы: будущиеУзлы, корни: [])
        var объёмКонечныхУзлов = 0
        for узел in будущиеУзлы {
            guard узел.байты.count <= 134_217_728 - объёмКонечныхУзлов else {
                throw ОтказОбщейМиграции.условие("предел-конечных-узлов-Docs")
            }
            объёмКонечныхУзлов += узел.байты.count
        }
        guard !будущаяСтруктура.препятствия.contains(where: { $0.код.contains("коллизия") }) else {
            throw ОтказОбщейМиграции.условие("алиасы-конечного-состава-Docs")
        }
        let будущиеДокументы = Dictionary(uniqueKeysWithValues: будущиеУзлы.filter { ($0.путь as NSString).pathExtension.lowercased() == "md" }.map { итог in
            let члены = группы[Data(итог.путь.utf8)] ?? []
            let канонический = члены.first(where: { Data($0.путь.utf8) == Data(итог.путь.utf8) }) ?? члены.first
            let разрешённыеЦели = нормализованные[итог.путь]?.целиПосле
                ?? канонический.flatMap { нормализованные[$0.путь]?.целиПосле } ?? []
            return (итог.путь, РазрешённыйДокументМиграции(байтыПосле: итог.байты, целиПосле: разрешённыеЦели, полнотаПроверена: true))
        })
        let будущийПлан = try ОбщийПланировщикПутей.построить(основа: основа, ожидаемаяОснова: ожидаемаяОснова,
            узлы: будущиеУзлы, корни: [], документы: будущиеДокументы)
        препятствия += будущийПлан.препятствия
        var шаги: [ШагПакетаДокументации] = []
        func состояние(_ узел: УзелОбщейМиграции, путь: String? = nil, байты: Data? = nil) -> ОжиданиеУзлаДокументации {
            .init(путь: путь ?? узел.путь, вид: узел.вид.rawValue, режим: узел.режим,
                sha256: узел.вид == .файл ? хэшПутей(байты ?? узел.байты) : nil)
        }
        func нет(_ путь: String) -> ОжиданиеУзлаДокументации { .init(путь: путь, вид: "отсутствует") }
        func шаг(_ действие: ДействиеПакетаДокументации, _ исходный: String?, _ целевой: String,
            _ до: [ОжиданиеУзлаДокументации], _ после: [ОжиданиеУзлаДокументации], _ байты: Data? = nil) {
            шаги.append(.init(номер: шаги.count + 1, действие: действие, исходный: исходный,
                целевой: целевой, до: до, после: после, байтыПосле: байты))
        }
        // Сначала все новые каталоги сверху вниз, затем реальные git mv.
        let каталоги = будущиеУзлы.filter { $0.вид == .каталог && поПути[Data($0.путь.utf8)] == nil }.sorted {
            let левая = $0.путь.split(separator: "/").count, правая = $1.путь.split(separator: "/").count
            return левая == правая ? порядокПутей($0.путь, $1.путь) : левая < правая
        }
        for каталог in каталоги { шаг(.создатьКаталог, nil, каталог.путь, [нет(каталог.путь)], [состояние(каталог)]) }
        for узел in упорядоченные where узел.вид == .файл && относится(узел.путь, к: верх) {
            let цель = назначение(узел.путь)
            if поПути[Data(цель.utf8)] == nil {
                шаг(.перенестиФайл, узел.путь, цель, [состояние(узел), нет(цель)], [нет(узел.путь), состояние(узел, путь: цель)])
            }
        }
        // Итоговые байты устанавливаются лишь один раз на назначение; occupied
        // canonical target выбирается явно, никогда победителем сортировки.
        for итог in будущиеУзлы.sorted(by: { порядокПутей($0.путь, $1.путь) }) where итог.вид == .файл {
            let члены = группы[Data(итог.путь.utf8)]!
            let до = члены.first(where: { Data($0.путь.utf8) == Data(итог.путь.utf8) }) ?? члены[0]
            if итог.байты != до.байты {
                шаг(.заменитьБайты, nil, итог.путь, [состояние(до, путь: итог.путь)], [состояние(итог)], итог.байты)
            }
        }
        // Схлопывание не означает mv -f. Backend обязан сохранить recoverable
        // source/index до удаления и проверить точный source и canonical target.
        for узел in упорядоченные where узел.вид == .файл && относится(узел.путь, к: верх) {
            let цель = назначение(узел.путь)
            if let целевой = поПути[Data(цель.utf8)], целевой.вид == .файл {
                guard let итог = будущиеУзлы.first(where: { Data($0.путь.utf8) == Data(цель.utf8) }) else {
                    throw ОтказОбщейМиграции.условие("нет-конечной-цели-схлопывания-Docs")
                }
                let после = состояние(итог)
                шаг(.схлопнутьКопию, узел.путь, цель, [состояние(узел), после], [нет(узел.путь), после])
            }
        }
        let пустые = упорядоченные.filter { $0.вид == .каталог && относится($0.путь, к: верх) }.sorted {
            let левая = $0.путь.split(separator: "/").count, правая = $1.путь.split(separator: "/").count
            return левая == правая ? порядокПутей($0.путь, $1.путь) : левая > правая
        }
        for каталог in пустые {
            шаг(.удалитьПустойКаталог, каталог.путь, каталог.путь, [состояние(каталог)], [нет(каталог.путь)])
        }
        let внешние = входящие.compactMap { документ -> ПравкаДляВладельцаДокументации? in
            guard let итог = нормализованные[документ.путь], итог.байтыПосле != документ.байты else { return nil }
            return .init(путь: документ.путь, исходныйSHA256: документ.sha256,
                будущиеБайты: итог.байтыПосле, будущийSHA256: хэшПутей(итог.байтыПосле))
        }.sorted { порядокПутей($0.путь, $1.путь) }
        return .init(основа: основа, исходныеУзлы: упорядоченные, индексДо: индексДо,
            исходноеПространство: пространство.sorted { $0.lexicographicallyPrecedes($1) },
            конечноеПространство: конечное.sorted { $0.lexicographicallyPrecedes($1) },
            отображения: отображения, каноны: каноны.sorted { порядокПутей($0.исходный, $1.исходный) },
            слияниеREADME: слияниеREADME,
            входящиеДо: входящие.map { .init(путь: $0.путь, байты: $0.байты, sha256: $0.sha256) }.sorted { порядокПутей($0.путь, $1.путь) },
            времяСвежести: времяСвежести,
            нормализованные: нормализованные, шаги: шаги, внешниеПравки: внешние,
            препятствия: препятствия.sorted { $0.код == $1.код ? порядокПутей($0.пути.joined(separator: "\0"), $1.пути.joined(separator: "\0")) : порядокПутей($0.код, $1.код) })
    }

    private static func телоREADME(_ байты: Data) throws -> String {
        guard var текст = String(data: байты, encoding: .utf8), !текст.contains("\r") else {
            throw ОтказОбщейМиграции.условие("нужен-LF-README-для-адресного-слияния")
        }
        // Footer проверен общей функцией выше, когда он присутствует.
        if let начало = текст.range(of: "<!-- FUM-MD-RECENCY:BEGIN -->") { текст = String(текст[..<начало.lowerBound]) }
        return текст.trimmingCharacters(in: .newlines)
    }

    private static func обновитьСвежесть(_ байты: Data, путь: String, время: String?) throws -> Data {
        guard let текст = String(data: байты, encoding: .utf8) else { throw ОтказОбщейМиграции.условие("не-UTF8-свежесть-Docs") }
        let естьМетки = текст.contains("FUM-MD-RECENCY:BEGIN") || текст.contains("FUM-MD-RECENCY:END")
        guard естьМетки else { return байты }
        guard let время else { throw ОтказОбщейМиграции.условие("нужно-явное-время-свежести-Docs") }
        let шаблон = #"(?:\A|\r?\n)<!-- FUM-MD-RECENCY:BEGIN -->\r?\n<!-- last-content-edit: ([^>]+) -->\r?\n<!-- content-sha256: sha256:([0-9a-f]{64}) -->\r?\n<!-- FUM-MD-RECENCY:END -->\r?\n?\z"#
        let выражение = try NSRegularExpression(pattern: шаблон)
        guard текст.components(separatedBy: "FUM-MD-RECENCY:BEGIN").count == 2,
              текст.components(separatedBy: "FUM-MD-RECENCY:END").count == 2,
              выражение.firstMatch(in: текст, range: NSRange(текст.startIndex..., in: текст)) != nil else {
            throw ОтказОбщейМиграции.условие("повреждённая-свежесть-Docs")
        }
        let естьCR = байты.contains(13)
        let единые = текст.replacingOccurrences(of: "\r\n", with: "\n")
        guard !единые.contains("\r"), !естьCR || Data(единые.replacingOccurrences(of: "\n", with: "\r\n").utf8) == байты else {
            throw ОтказОбщейМиграции.условие("смешанные-переводы-строк-Docs")
        }
        let обновлённые = try РешательСсылокПакета.обновитьСвежесть(Data(единые.utf8), путь: путь, время: время)
        let результат = естьCR ? Data(String(decoding: обновлённые, as: UTF8.self).replacingOccurrences(of: "\n", with: "\r\n").utf8) : обновлённые
        guard результат.count <= 8_388_608 else { throw ОтказОбщейМиграции.условие("предел-результата-свежести-Docs") }
        return результат
    }

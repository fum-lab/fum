enum ЧитательДокументовКорпуса {
    static func снять(корень: URL, ожидание: Data, собственныйИсточник: Data,
        передСнимкомДляПроверки: (() throws -> Void)? = nil, послеСнимкаДляПроверки: (() throws -> Void)? = nil,
        послеИнвентаризацииДляПроверки: (() throws -> Void)? = nil) throws -> ПрочитанныйКорпусДокументов {
        _ = try ТокеныJSONМиграции.разобрать(ожидание); _ = try ТокеныJSONМиграции.разобрать(собственныйИсточник)
        let вход = try JSONDecoder().decode(ОжиданиеСнимкаКорпуса.self, from: ожидание)
        let собственный = try JSONDecoder().decode(ИсточникСобственныхДокументов.self, from: собственныйИсточник)
        guard вход.схема == "fum.независимый-манифест-корпуса.1", (1...8192).contains(вход.документы.count),
              вход.политикаГраницХэш == "5a52f1134876854e29db243cbfc6eebc86cc916a4d354ba73a0fc7516109bcd4" else { throw ОтказКорпусаСсылок.условие("неверное-ожидание-снимка") }
        return try снятьПроверенное(корень: корень, вход: вход, ожидание: ожидание, собственныйИсточник: собственныйИсточник, собственный: собственный,
            передСнимкомДляПроверки: передСнимкомДляПроверки, послеСнимкаДляПроверки: послеСнимкаДляПроверки,
            послеИнвентаризацииДляПроверки: послеИнвентаризацииДляПроверки)
    }

    private static func снятьПроверенное(корень: URL, вход: ОжиданиеСнимкаКорпуса, ожидание: Data, собственныйИсточник: Data, собственный: ИсточникСобственныхДокументов,
        передСнимкомДляПроверки: (() throws -> Void)?, послеСнимкаДляПроверки: (() throws -> Void)?,
        послеИнвентаризацииДляПроверки: (() throws -> Void)?) throws -> ПрочитанныйКорпусДокументов {
        _ = try ОбщийПланировщикПутей.построить(основа: вход.основа, ожидаемаяОснова: вход.основа, узлы: [], корни: [])
        guard собственный.схема == "fum.private-source-checkpoint.1", Data(собственный.корень.utf8) == Data(корень.path.utf8),
              собственный.коммит == вход.основа.коммит, Data(собственный.ветка.utf8) == Data(вход.основа.ветка.utf8),
              хэшПутей(собственныйИсточник) == вход.источникСобственныхХэш else { throw ОтказКорпусаСсылок.условие("нет-отдельной-опоры-собственных-документов") }
        var разрешённые: [Data: ЗаписьСобственногоДокумента] = [:]
        for запись in собственный.файлы + собственный.открытыйЖурнал where (запись.путь as NSString).pathExtension == "md" {
            try ИменаПутей.проверитьПуть(запись.путь)
            guard разрешённые.updateValue(запись, forKey: Data(запись.путь.utf8)) == nil else { throw ОтказКорпусаСсылок.условие("повтор-собственного-документа") }
        }
        var ожидаемые: [Data: ФайлОжиданияКорпуса] = [:], сумма = 0
        for запись in вход.документы {
            try ИменаПутей.проверитьПуть(запись.путь)
            guard (запись.путь as NSString).pathExtension == "md", ["100644", "100755"].contains(запись.режим),
                  запись.размер >= 0, запись.размер <= 33_554_432, запись.размер <= 134_217_728 - сумма,
                  запись.хэш.range(of: #"\A[0-9a-f]{64}\z"#, options: .regularExpression) != nil, !запись.происхождение.isEmpty,
                  ожидаемые.updateValue(запись, forKey: Data(запись.путь.utf8)) == nil else { throw ОтказКорпусаСсылок.условие("неверная-запись-ожидания") }
            сумма += запись.размер
            if запись.класс == "отслеживаемый" {
                guard запись.объект?.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil else { throw ОтказКорпусаСсылок.условие("нет-Git-объекта-документа") }
            } else {
                guard запись.класс == "собственный-неотслеживаемый", запись.объект == nil, let опора = разрешённые[Data(запись.путь.utf8)],
                      опора.хэш == запись.хэш, опора.размер == запись.размер, (опора.режим ?? "100644") == запись.режим else { throw ОтказКорпусаСсылок.условие("не-подтверждён-собственный-документ") }
            }
        }
        let политика = try ПолитикаГраницПутей.принятая()
        let индексДо = try ЧитательПутей.гит(корень, ["ls-files", "--stage", "-z"]).0
        guard хэшПутей(индексДо) == вход.основа.индексSHA256 else { throw ОтказКорпусаСсылок.условие("дрейф-индекса-корпуса") }
        let индекс = try разобратьИндекс(индексДо)
        let полныеДо = try ЧитательПутей.гит(корень, ["ls-files", "--cached", "--others", "-z"]).0
        guard полныеДо.count <= 16_777_216, хэшПутей(полныеДо) == вход.всеМетаданныеХэш else { throw ОтказКорпусаСсылок.условие("дрейф-полной-инвентаризации") }
        let составДо = try состав(полныеДо, индекс: индекс, политика: политика, собственные: разрешённые)
        guard Set(составДо.документы.keys) == Set(ожидаемые.keys), составДо.документы.allSatisfy({ ожидаемые[$0.key]?.класс == $0.value }) else { throw ОтказКорпусаСсылок.условие("неполный-состав-документов") }
        try передСнимкомДляПроверки?()
        // Каждый дополнительный байтовый алиас проходит заключительную проверку
        // области: точное открытие и сверку метаданных с физическим именем.
        let области = Set(вход.документы.map { Data($0.путь.utf8) } + составДо.алиасы.keys).sorted { $0.lexicographicallyPrecedes($1) }.map { String(decoding: $0, as: UTF8.self) }
        let чтение = try ЧитательПутей.снять(корень: корень, области: области, политика: политика, пределСохраняемогоФайла: 33_554_432, пределВсехБайтов: 134_217_728,
            пределЧитаемогоФайла: 33_554_432,
            послеЧтенияДляПроверки: послеСнимкаДляПроверки)
        let снимок = чтение.снимок
        let фактическаяОснова = ОсноваОбщейМиграции(корневаяЗадача: вход.основа.корневаяЗадача, владелец: вход.основа.владелец,
            ветка: снимок.ветка, коммит: снимок.коммит, дерево: снимок.дерево, индексSHA256: снимок.индекс_sha256)
        guard try байтыПлана(фактическаяОснова) == байтыПлана(вход.основа), !снимок.индекс_изменён else { throw ОтказКорпусаСсылок.условие("дрейф-основы-снимка-корпуса") }
        let поНФС = Dictionary(grouping: ожидаемые.keys, by: { Data(String(decoding: $0, as: UTF8.self).precomposedStringWithCanonicalMapping.utf8) })
        guard !поНФС.values.contains(where: { $0.count != 1 }) else { throw ОтказКорпусаСсылок.условие("алиасы-ожидаемых-документов") }
        var документы: [Data: ДокументКорпусаМиграции] = [:], записи: [ЗаписьФизическогоКорпуса] = []
        for запись in снимок.записи where запись.тип == "файл" {
            let кандидаты = поНФС[Data(запись.путь.precomposedStringWithCanonicalMapping.utf8)] ?? []
            guard кандидаты.count == 1, let ключ = кандидаты.first, let ожидаемая = ожидаемые[ключ],
                  let данные = чтение.тексты[Data(запись.путь.utf8)], данные.count == ожидаемая.размер,
                  хэшПутей(данные) == ожидаемая.хэш, запись.sha256 == ожидаемая.хэш, запись.режим == ожидаемая.режим else {
                throw ОтказКорпусаСсылок.условие("не-совпали-физические-байты-документа")
            }
            if ожидаемая.класс == "отслеживаемый" {
                let объект = Insecure.SHA1.hash(data: Data("blob \(данные.count)\0".utf8) + данные).map { String(format: "%02x", $0) }.joined()
                guard запись.путь_индекса.map({ Data($0.utf8) }) == ключ, запись.объект == ожидаемая.объект, объект == ожидаемая.объект,
                      запись.режим_индекса == ожидаемая.режим else { throw ОтказКорпусаСсылок.условие("не-совпал-Git-источник-документа") }
            } else if запись.путь_индекса != nil || запись.объект != nil { throw ОтказКорпусаСсылок.условие("изменился-класс-собственного-документа") }
            guard документы.updateValue(.init(путь: ожидаемая.путь, байты: данные, роль: .неизвестный, основаниеРоли: "роль ещё не назначена", режим: ожидаемая.режим), forKey: ключ) == nil else { throw ОтказКорпусаСсылок.условие("повтор-физического-документа") }
            записи.append(.init(путь: ожидаемая.путь, физическийПуть: запись.путь, хэш: ожидаемая.хэш, режим: ожидаемая.режим, размер: данные.count, класс: ожидаемая.класс))
        }
        guard Set(документы.keys) == Set(ожидаемые.keys) else { throw ОтказКорпусаСсылок.условие("не-прочитан-весь-корпус") }
        let полныеПосле = try ЧитательПутей.гит(корень, ["ls-files", "--cached", "--others", "-z"]).0
        guard полныеПосле == полныеДо, try ЧитательПутей.гит(корень, ["ls-files", "--stage", "-z"]).0 == индексДо,
              try состав(полныеПосле, индекс: индекс, политика: политика, собственные: разрешённые) == составДо else { throw ОтказКорпусаСсылок.условие("поздний-дрейф-полной-инвентаризации") }
        try послеИнвентаризацииДляПроверки?()
        guard try ЧитательПутей.гит(корень, ["rev-parse", "HEAD"]).0 == Data((вход.основа.коммит + "\n").utf8),
              try ЧитательПутей.гит(корень, ["symbolic-ref", "HEAD"]).0 == Data((вход.основа.ветка + "\n").utf8) else { throw ОтказКорпусаСсылок.условие("поздний-дрейф-HEAD-или-ref-корпуса") }
        let ключи = документы.keys.sorted { $0.lexicographicallyPrecedes($1) }
        var квитанция = КвитанцияСнимкаКорпуса(основа: вход.основа, хэшОжидания: хэшПутей(ожидание), физическоеПространствоХэш: снимок.пространство_sha256,
            документы: записи.sorted { порядокПутей($0.путь, $1.путь) })
        квитанция.алиасыИнвентаризации = составДо.алиасы.map { .init(путьМетаданных: String(decoding: $0.key, as: UTF8.self), логическийПуть: String(decoding: $0.value, as: UTF8.self)) }.sorted { порядокПутей($0.путьМетаданных, $1.путьМетаданных) }
        квитанция.точноОткрытыеОбласти = чтение.точноОткрытыеОбласти
        квитанция.учётБайтовПроверен = true
        return .init(квитанция: квитанция, документы: ключи.map { документы[$0]! })
    }

    static func разобратьИндекс(_ данные: Data) throws -> [Data: (режим: String, объект: String)] {
        guard данные.count <= 16_777_216 else { throw ОтказКорпусаСсылок.условие("предел-индекса") }
        var записи: [Data: (String, String)] = [:]
        for сырая in данные.split(separator: 0) {
            guard let строка = String(data: сырая, encoding: .utf8), let табуляция = строка.firstIndex(of: "\t") else { throw ОтказКорпусаСсылок.условие("неверный-индекс-корпуса") }
            let поля = строка[..<табуляция].split(separator: " "), путь = String(строка[строка.index(after: табуляция)...])
            guard поля.count == 3, поля[2] == "0", записи.updateValue((String(поля[0]), String(поля[1])), forKey: Data(путь.utf8)) == nil else { throw ОтказКорпусаСсылок.условие("не-замкнутый-stage0-корпуса") }
        }
        return записи
    }
    static func состав(_ данные: Data, индекс: [Data: (режим: String, объект: String)], политика: ПолитикаГраницПутей,
        собственные: [Data: ЗаписьСобственногоДокумента]) throws -> СоставИнвентаризацииКорпуса {
        var результат: [Data: String] = [:], алиасы: [Data: Data] = [:], сырые: Set<Data> = []
        let индексПоНФС = Dictionary(grouping: индекс.keys, by: { Data(String(decoding: $0, as: UTF8.self).precomposedStringWithCanonicalMapping.utf8) })
        let своиПоНФС = Dictionary(grouping: собственные.keys, by: { Data(String(decoding: $0, as: UTF8.self).precomposedStringWithCanonicalMapping.utf8) })
        let внешние = индекс.filter { $0.value.режим == "160000" }.keys.map { String(decoding: $0, as: UTF8.self).precomposedStringWithCanonicalMapping }
        for сырая in данные.split(separator: 0) {
            guard let путь = String(data: сырая, encoding: .utf8) else { throw ОтказКорпусаСсылок.условие("не-UTF8-метаданные-корпуса") }
            guard (путь as NSString).pathExtension == "md" else { continue }
            let нормальный = путь.precomposedStringWithCanonicalMapping
            if политика.граница(нормальный, каталог: false) || внешние.contains(where: { ИменаПутей.вложен(нормальный, в: $0) }) { continue }
            var предок = (нормальный as NSString).deletingLastPathComponent, исключён = false
            while !предок.isEmpty {
                if политика.граница(предок, каталог: true) { исключён = true; break }
                предок = (предок as NSString).deletingLastPathComponent
            }
            if исключён { continue }
            let сыройКлюч = Data(путь.utf8), нфс = Data(нормальный.utf8)
            guard сырые.insert(сыройКлюч).inserted else { throw ОтказКорпусаСсылок.условие("повтор-сырого-пути-инвентаризации") }
            var ключ = сыройКлюч
            if индекс[ключ] == nil, собственные[ключ] == nil {
                let кандидаты = (индексПоНФС[нфс] ?? []) + (своиПоНФС[нфс] ?? [])
                guard кандидаты.count == 1, let кандидат = кандидаты.first else { throw ОтказКорпусаСсылок.условие("не-допущен-неотслеживаемый-документ") }
                ключ = кандидат; алиасы[сыройКлюч] = ключ
            }
            let класс: String
            if let запись = индекс[ключ] {
                guard ["100644", "100755"].contains(запись.режим) else { throw ОтказКорпусаСсылок.условие("не-обычный-отслеживаемый-документ") }
                класс = "отслеживаемый"
            } else {
                guard собственные[ключ] != nil else { throw ОтказКорпусаСсылок.условие("не-допущен-неотслеживаемый-документ") }
                класс = "собственный-неотслеживаемый"
            }
            if let прежний = результат[ключ], прежний != класс { throw ОтказКорпусаСсылок.условие("неоднозначный-класс-документа") }
            результат[ключ] = класс
        }
        return .init(документы: результат, алиасы: алиасы)
    }
}

struct СоставИнвентаризацииКорпуса: Equatable {
    var документы: [Data: String]
    var алиасы: [Data: Data]
}

struct ИсточникСобственныхДокументов: Decodable {
    var схема: String
    var корень: String
    var коммит: String
    var ветка: String
    var файлы: [ЗаписьСобственногоДокумента]
    var открытыйЖурнал: [ЗаписьСобственногоДокумента]
    enum CodingKeys: String, CodingKey { case схема = "schema", корень = "root", коммит = "HEAD", ветка = "ref", файлы = "files", открытыйЖурнал = "openJournal" }
}
struct ЗаписьСобственногоДокумента: Decodable {
    var путь: String
    var хэш: String
    var размер: Int
    var режим: String?
    enum CodingKeys: String, CodingKey { case путь = "path", хэш = "sha256", размер = "bytes", режим = "mode" }
}

#if ФУМ_СНИМОК_КОРПУСА_КОМАНДА
@main struct ЗапускСнимкаКорпуса {
    static func main() {
        do {
            guard CommandLine.arguments.count == 3 else { throw ОтказКорпусаСсылок.условие("нужны-физический-корень-и-отдельный-источник-собственных-входов") }
            let ожидание = try ограниченно(FileHandle.standardInput)
            let источник = try FileHandle(forReadingFrom: URL(fileURLWithPath: CommandLine.arguments[2]))
            defer { try? источник.close() }
            let собственный = try ограниченно(источник)
            let начало = DispatchTime.now().uptimeNanoseconds
            try FileHandle.standardError.write(contentsOf: Data("корпус: начало читающего снимка\n".utf8))
            let результат = try ЧитательДокументовКорпуса.снять(корень: URL(fileURLWithPath: CommandLine.arguments[1]), ожидание: ожидание, собственныйИсточник: собственный)
            try FileHandle.standardOutput.write(contentsOf: байтыПлана(результат.квитанция))
            try FileHandle.standardError.write(contentsOf: Data("корпус: учтено \(результат.документы.count); \(DispatchTime.now().uptimeNanoseconds - начало) нс; роли и ссылки не проверены\n".utf8))
        } catch {
            try? FileHandle.standardError.write(contentsOf: Data("корпус: отказ \(error)\n".utf8)); exit(2)
        }
    }
    private static func ограниченно(_ ручка: FileHandle) throws -> Data {
        var данные = Data()
        while let часть = try ручка.read(upToCount: 1_048_576), !часть.isEmpty {
            guard часть.count <= 4_194_304 - данные.count else { throw ОтказКорпусаСсылок.условие("предел-входного-JSON") }
            данные.append(часть)
        }
        return данные
    }
}

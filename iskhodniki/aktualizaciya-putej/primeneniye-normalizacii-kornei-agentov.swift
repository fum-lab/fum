import Foundation
import CryptoKit
import Darwin

enum СистемаФайловНормализации {
    private struct ОткрытыйПуть {
        let родитель: Int32
        let имя: String
        let описание: Int32
    }

    static func отпечаток(
        корень: URL,
        путь: String
    ) throws -> ОтпечатокФайловойСистемыНормализации? {
        guard let открытый = try открыть(корень: корень, путь: путь, допускаетсяОтсутствие: true) else {
            return nil
        }
        defer {
            close(открытый.описание)
            close(открытый.родитель)
        }
        return try отпечаток(открытый.описание)
    }

    static func прочитать(
        корень: URL,
        путь: String,
        предел: Int
    ) throws -> (байты: Data, режим: mode_t, отпечаток: ОтпечатокФайловойСистемыНормализации) {
        guard let открытый = try открыть(корень: корень, путь: путь, допускаетсяОтсутствие: false) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("отсутствует-файл: " + путь)
        }
        defer {
            close(открытый.описание)
            close(открытый.родитель)
        }
        let до = try состояние(открытый.описание)
        guard до.st_mode & S_IFMT == S_IFREG,
              до.st_nlink == 1,
              до.st_size >= 0,
              до.st_size <= Int64(предел) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("необычный-или-чрезмерный-файл: " + путь)
        }
        var байты = Data()
        байты.reserveCapacity(Int(до.st_size))
        var буфер = [UInt8](repeating: 0, count: 65_536)
        while true {
            let число = буфер.withUnsafeMutableBytes { указатель in
                read(открытый.описание, указатель.baseAddress, указатель.count)
            }
            if число == 0 { break }
            if число < 0 {
                if errno == EINTR { continue }
                throw ОшибкаНормализацииКорнейАгентов.условие("не прочитан-файл: " + путь)
            }
            байты.append(contentsOf: буфер.prefix(число))
            guard байты.count <= предел else {
                throw ОшибкаНормализацииКорнейАгентов.условие("превышен-предел-файла: " + путь)
            }
        }
        let после = try состояние(открытый.описание)
        guard равны(до, после), Int64(байты.count) == Int64(до.st_size) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-файла-при-чтении: " + путь)
        }
        return (байты, до.st_mode, try отпечаток(после))
    }

    static func записатьАтомарно(
        _ байты: Data,
        корень: URL,
        путь: String,
        режим: mode_t,
        operationID: String,
        номерШага: Int
    ) throws {
        guard номерШага >= 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неверный-идентификатор-временного-файла")
        }
        let (родитель, имя) = try открытьРодителя(корень: корень, путь: путь)
        defer { close(родитель) }
        try проверитьТочноеИмя(родитель, имя)
        let меткаВременногоФайла = SHA256.hash(data: Data(operationID.utf8)).map { String(format: "%02x", $0) }.joined()
        let временноеИмя = ".fum-normalizaciya-\(меткаВременногоФайла)-\(номерШага).tmp"
        guard try проверитьТочноеИмя(родитель, временноеИмя) == false else {
            throw ОшибкаНормализацииКорнейАгентов.условие("оставшийся-временный-файл-неизвестного-исхода")
        }
        let дескриптор = openat(
            родитель,
            временноеИмя,
            O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW,
            режим & 0o7777)
        guard дескриптор >= 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("не-создан-временный-файл")
        }
        var переименован = false
        defer {
            close(дескриптор)
            if !переименован { _ = unlinkat(родитель, временноеИмя, 0) }
        }
        try записать(байты, в: дескриптор)
        guard fchmod(дескриптор, режим & 0o7777) == 0, fsync(дескриптор) == 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("не-сохранён-временный-файл")
        }
        guard renameat(родитель, временноеИмя, родитель, имя) == 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("не-заменён-файл")
        }
        переименован = true
        guard fsync(родитель) == 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("не-сохранён-каталог-файла")
        }
    }

    private static func открыть(
        корень: URL,
        путь: String,
        допускаетсяОтсутствие: Bool
    ) throws -> ОткрытыйПуть? {
        try ИменаПутей.проверитьПуть(путь)
        let начальный = open(корень.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW)
        guard начальный >= 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("не-открыт-физический-корень")
        }
        var состояниеКорня = stat()
        guard fstat(начальный, &состояниеКорня) == 0,
              состояниеКорня.st_mode & S_IFMT == S_IFDIR else {
            close(начальный)
            throw ОшибкаНормализацииКорнейАгентов.условие("корень-не-физический-каталог")
        }
        var текущий = начальный
        let части = ИменаПутей.компоненты(путь, сохранятьПустые: true)
        for (номер, имя) in части.enumerated() {
            guard !имя.isEmpty else {
                close(текущий)
                throw ОшибкаНормализацииКорнейАгентов.условие("пустой-компонент-пути")
            }
            guard try проверитьТочноеИмя(текущий, имя) else {
                close(текущий)
                if допускаетсяОтсутствие { return nil }
                throw ОшибкаНормализацииКорнейАгентов.условие("отсутствует-точный-путь: " + путь)
            }
            let последний = номер == части.count - 1
            let флаги = O_RDONLY | O_NOFOLLOW | O_NONBLOCK | (последний ? 0 : O_DIRECTORY)
            let следующий = openat(текущий, имя, флаги)
            guard следующий >= 0 else {
                let ошибка = errno
                close(текущий)
                if допускаетсяОтсутствие && ошибка == ENOENT { return nil }
                throw ОшибкаНормализацииКорнейАгентов.условие("не-открыт-точный-путь: " + путь)
            }
            if последний {
                let родитель = текущий
                return ОткрытыйПуть(родитель: родитель, имя: имя, описание: следующий)
            }
            close(текущий)
            текущий = следующий
        }
        close(текущий)
        throw ОшибкаНормализацииКорнейАгентов.условие("пустой-точный-путь")
    }

    private static func открытьРодителя(корень: URL, путь: String) throws -> (Int32, String) {
        try ИменаПутей.проверитьПуть(путь)
        let части = ИменаПутей.компоненты(путь, сохранятьПустые: true)
        guard let имя = части.last, части.count > 1 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("нет-родителя-файла")
        }
        let родительПуть = части.dropLast().joined(separator: "/")
        guard let открытый = try открыть(корень: корень, путь: родительПуть, допускаетсяОтсутствие: false) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("отсутствует-родитель-файла")
        }
        let вид = try состояние(открытый.описание).st_mode & S_IFMT
        guard вид == S_IFDIR else {
            close(открытый.описание)
            close(открытый.родитель)
            throw ОшибкаНормализацииКорнейАгентов.условие("родитель-файла-не-каталог")
        }
        close(открытый.родитель)
        return (открытый.описание, имя)
    }

    @discardableResult
    private static func проверитьТочноеИмя(_ каталог: Int32, _ искомое: String) throws -> Bool {
        let копия = dup(каталог)
        guard копия >= 0, let перечисление = fdopendir(копия) else {
            if копия >= 0 { close(копия) }
            throw ОшибкаНормализацииКорнейАгентов.условие("не-перечислен-каталог-пути")
        }
        defer { closedir(перечисление) }
        rewinddir(перечисление)
        var найдено = false
        errno = 0
        while let запись = readdir(перечисление) {
            var имя = запись.pointee.d_name
            let байты = withUnsafeBytes(of: &имя) { буфер in
                Data(буфер.prefix(while: { $0 != 0 }))
            }
            guard let текст = String(data: байты, encoding: .utf8) else {
                throw ОшибкаНормализацииКорнейАгентов.условие("не-UTF8-имя-каталога")
            }
            if Data(текст.utf8) == Data(искомое.utf8) { найдено = true }
            errno = 0
        }
        guard errno == 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неполный-обход-компонентов-пути")
        }
        return найдено
    }

    private static func состояние(_ дескриптор: Int32) throws -> stat {
        var значение = stat()
        guard fstat(дескриптор, &значение) == 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("не-снят-отпечаток-файла")
        }
        return значение
    }

    private static func отпечаток(_ значение: stat) throws -> ОтпечатокФайловойСистемыНормализации {
        guard значение.st_size >= 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("отрицательный-размер-узла")
        }
        return ОтпечатокФайловойСистемыНормализации(
            устройство: UInt64(значение.st_dev),
            inode: UInt64(значение.st_ino),
            типИРежим: UInt32(значение.st_mode),
            размер: Int64(значение.st_size),
            изменениеСекунды: Int64(значение.st_mtimespec.tv_sec),
            изменениеНаносекунды: Int64(значение.st_mtimespec.tv_nsec))
    }

    private static func равны(_ левый: stat, _ правый: stat) -> Bool {
        левый.st_dev == правый.st_dev
            && левый.st_ino == правый.st_ino
            && левый.st_mode == правый.st_mode
            && левый.st_nlink == правый.st_nlink
            && левый.st_size == правый.st_size
            && левый.st_mtimespec.tv_sec == правый.st_mtimespec.tv_sec
            && левый.st_mtimespec.tv_nsec == правый.st_mtimespec.tv_nsec
            && левый.st_ctimespec.tv_sec == правый.st_ctimespec.tv_sec
            && левый.st_ctimespec.tv_nsec == правый.st_ctimespec.tv_nsec
    }

    private static func записать(_ байты: Data, в дескриптор: Int32) throws {
        try байты.withUnsafeBytes { буфер in
            guard let база = буфер.baseAddress else { return }
            var смещение = 0
            while смещение < буфер.count {
                let число = write(дескриптор, база.advanced(by: смещение), буфер.count - смещение)
                if число < 0 && errno == EINTR { continue }
                guard число > 0 else {
                    throw ОшибкаНормализацииКорнейАгентов.условие("не-записаны-байты-документа")
                }
                смещение += число
            }
        }
    }
}

enum НормализацияСсылок {
    static func переписать(_ байты: Data, шаги: [ШагНормализацииКорняАгента]) -> Data {
        let отображения: [(старое: Data, новое: Data, каталог: Bool)] = шаги.compactMap { шаг in
            switch шаг.вид {
            case .переносКаталога, .удалениеДубликатаКаталога:
                return (Data((шаг.исходныйПуть + "/").utf8), Data((шаг.целевойПуть + "/").utf8), true)
            case .переносФайла, .удалениеДубликатаФайла:
                return (Data(шаг.исходныйПуть.utf8), Data(шаг.целевойПуть.utf8), false)
            case .конфликтСохранён, .обновлениеДокумента:
                return nil
            }
        }.sorted { $0.старое.count > $1.старое.count }
        var результат = Data()
        var курсор = байты.startIndex
        while курсор < байты.endIndex {
            let совпадение = отображения.first { отображение in
                let остаток = байты[курсор..<байты.endIndex]
                guard остаток.starts(with: отображение.старое) else { return false }
                guard !отображение.каталог else {
                    return курсор == байты.startIndex || граница(байты[байты.index(before: курсор)])
                }
                let конец = байты.index(курсор, offsetBy: отображение.старое.count)
                guard курсор == байты.startIndex || граница(байты[байты.index(before: курсор)]) else { return false }
                guard конец != байты.endIndex else { return true }
                return !символПути(байты[конец])
            }
            if let совпадение {
                результат.append(совпадение.новое)
                курсор = байты.index(курсор, offsetBy: совпадение.старое.count)
            } else {
                результат.append(байты[курсор])
                курсор = байты.index(after: курсор)
            }
        }
        return результат
    }

    private static func граница(_ байт: UInt8) -> Bool {
        [9, 10, 13, 32, 34, 39, 40, 41, 44, 58, 59, 60, 61, 62, 91, 93, 96, 123, 125].contains(байт)
    }

    private static func символПути(_ байт: UInt8) -> Bool {
        байт == 47 || байт == 45 || байт == 46 || байт == 95
            || (48...57).contains(байт) || (65...90).contains(байт) || (97...122).contains(байт)
            || байт >= 128
    }
}

private enum ОшибкаПодтвержденияКонтрольнойТочки: Error {
    case неПодтверждено
}

enum ИсполнительНормализацииКорнейАгентов {
    static func выполнить(
        назначение: НазначениеНормализацииКорнейАгентов,
        контрольнаяТочка: КонтрольнаяТочкаНормализацииКорнейАгентов?,
        сохранитьИПеречитать: @Sendable (
            КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
        ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
    ) async throws -> РезультатНормализацииКорнейАгентов {
        let корень = URL(fileURLWithPath: назначение.кореньРепозитория, isDirectory: true)
        var точка: КонтрольнаяТочкаНормализацииКорнейАгентов
        if let сохранённая = контрольнаяТочка {
            точка = try await продолжить(
                сохранённая,
                назначение: назначение,
                корень: корень,
                сохранитьИПеречитать: сохранитьИПеречитать)
            if точка.фаза == .завершено {
                return .init(исход: .безИзменений, контрольнаяТочка: точка, изменённыеПути: [], конфликты: точка.конфликты)
            }
            if точка.фаза == .неизвестно {
                return .init(исход: .неизвестно, контрольнаяТочка: точка, изменённыеПути: [], конфликты: точка.конфликты)
            }
        } else {
            точка = try await ПланировщикНормализацииКорнейАгентов.построить(назначение)
            try await сохранить(точка, фаза: .намерение, callback: сохранитьИПеречитать)
        }

        while точка.следующийШаг < точка.шаги.count {
            let номер = точка.следующийШаг
            let шаг = точка.шаги[номер]
            do {
                точка = try await выполнить(шаг, номер: номер, точка: точка, корень: корень, назначение: назначение,
                    callback: сохранитьИПеречитать)
            } catch {
                return await неизвестныйИсход(
                    точка,
                    сохранять: !(error is ОшибкаПодтвержденияКонтрольнойТочки),
                    callback: сохранитьИПеречитать)
            }
        }
        do {
            точка.фаза = .завершено
            точка.итоговыйИндексSHA256 = try индексSHA(корень: корень, назначение: назначение)
            точка.итоговыеОтпечаткиКорней = try отпечаткиКорней(корень: корень, назначение: назначение)
            try проверитьКонечноеСостояние(точка, корень: корень, назначение: назначение)
            try await сохранить(точка, фаза: .терминал, callback: сохранитьИПеречитать)
        } catch {
            return await неизвестныйИсход(
                точка,
                сохранять: !(error is ОшибкаПодтвержденияКонтрольнойТочки),
                callback: сохранитьИПеречитать)
        }
        let исход: РезультатНормализацииКорнейАгентов.Исход
        if !точка.конфликты.isEmpty {
            исход = .конфликтСохранён
        } else if !точка.шаги.contains(where: {
            $0.вид == .переносФайла || $0.вид == .переносКаталога
                || $0.вид == .удалениеДубликатаФайла || $0.вид == .удалениеДубликатаКаталога
                || $0.вид == .обновлениеДокумента
        }) {
            исход = .безИзменений
        } else {
            исход = .перенос
        }
        return .init(
            исход: исход,
            контрольнаяТочка: точка,
            изменённыеПути: Array(Set(точка.шаги.compactMap { шаг in
                switch шаг.вид {
                case .переносФайла, .переносКаталога, .удалениеДубликатаФайла, .удалениеДубликатаКаталога, .обновлениеДокумента:
                    return шаг.целевойПуть
                case .конфликтСохранён:
                    return nil
                }
            })).sorted(by: порядок),
            конфликты: точка.конфликты)
    }

    private static func продолжить(
        _ исходнаяТочка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        назначение: НазначениеНормализацииКорнейАгентов,
        корень: URL,
        сохранитьИПеречитать callback: @Sendable (
            КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
        ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
    ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов {
        var точка = исходнаяТочка
        let назначениеSHA = ПланировщикНормализацииКорнейАгентов.хэш(
            try ПланировщикНормализацииКорнейАгентов.каноническиеБайты(назначение))
        let стабильныйID = ПланировщикНормализацииКорнейАгентов.сформироватьИдентификаторОперации(назначение)
        var основаПлана = точка
        основаПлана.планSHA256 = ""
        основаПлана.следующийШаг = 0
        основаПлана.фаза = .намерение
        основаПлана.итоговыйИндексSHA256 = точка.основа.индексSHA256
        основаПлана.итоговыеОтпечаткиКорней = [:]
        let пересчитанныйПланSHA = ПланировщикНормализацииКорнейАгентов.хэш(
            try ПланировщикНормализацииКорнейАгентов.каноническиеБайты(основаПлана))
        let входыДопускаКорректны: Bool
        do {
            try ПланировщикНормализацииКорнейАгентов.проверитьНазначение(назначение)
            try ПланировщикНормализацииКорнейАгентов.проверитьШагиВГраницахДопуска(
                точка.шаги, назначение: назначение)
            входыДопускаКорректны = true
        } catch {
            входыДопускаКорректны = false
        }
        guard точка.схема == "fum.контрольная-точка-нормализации-корней-агентов.2",
              входыДопускаКорректны,
              точка.operationID == стабильныйID,
              точка.назначениеSHA256 == назначениеSHA,
              точка.планSHA256 == пересчитанныйПланSHA,
              точка.допуск == назначение.допуск,
              точка.основа == назначение.снимок,
              точка.шаги.enumerated().allSatisfy({ $0.offset == $0.element.номер }),
              (0...точка.шаги.count).contains(точка.следующийШаг) else {
            return await неизвестнаяКонтрольнаяТочка(точка, сохранять: true, callback: callback)
        }
        if точка.фаза == .неизвестно { return точка }
        if точка.фаза == .завершено {
            do {
                try проверитьКороткийNOOP(точка, корень: корень, назначение: назначение)
            } catch {
                return await неизвестнаяКонтрольнаяТочка(точка, сохранять: true, callback: callback)
            }
            return точка
        }
        do {
            try проверитьИдентичностьGit(назначение, корень: корень)
            for номер in 0..<точка.следующийШаг {
                guard try шагУжеПрименён(точка.шаги[номер], номер: номер, корень: корень, точка: точка) else {
                    return await неизвестнаяКонтрольнаяТочка(точка, сохранять: true, callback: callback)
                }
            }
            let текущийИндекс = try индексSHA(корень: корень, назначение: назначение)
            if let ожидаемый = точка.итоговыйИндексSHA256, текущийИндекс != ожидаемый {
                let шаг = точка.шаги.indices.contains(точка.следующийШаг) ? точка.шаги[точка.следующийШаг] : nil
                if let шаг, try шагУжеПрименён(шаг, номер: точка.следующийШаг, корень: корень, точка: точка) {
                    точка.следующийШаг += 1
                    точка.итоговыйИндексSHA256 = текущийИндекс
                    точка.итоговыеОтпечаткиКорней = try отпечаткиКорней(корень: корень, назначение: назначение)
                    точка.фаза = .намерение
                    try await сохранить(точка, фаза: .подтверждённыйШаг, callback: callback)
                } else {
                    return await неизвестнаяКонтрольнаяТочка(точка, сохранять: true, callback: callback)
                }
            }
            if точка.фаза == .намерение,
               точка.шаги.indices.contains(точка.следующийШаг) {
                let следующий = точка.шаги[точка.следующийШаг]
                if try шагУжеПрименён(следующий, номер: точка.следующийШаг, корень: корень, точка: точка) {
                    точка.следующийШаг += 1
                    точка.итоговыйИндексSHA256 = try индексSHA(корень: корень, назначение: назначение)
                    точка.итоговыеОтпечаткиКорней = try отпечаткиКорней(корень: корень, назначение: назначение)
                    try await сохранить(точка, фаза: .подтверждённыйШаг, callback: callback)
                }
            }
        } catch {
            return await неизвестнаяКонтрольнаяТочка(
                точка,
                сохранять: !(error is ОшибкаПодтвержденияКонтрольнойТочки),
                callback: callback)
        }
        return точка
    }

    private static func выполнить(
        _ шаг: ШагНормализацииКорняАгента,
        номер: Int,
        точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов,
        callback: @Sendable (
            КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
        ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
    ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов {
        var итог = точка
        try проверитьИдентичностьGit(назначение, корень: корень)
        let текущийSHA = try индексSHA(корень: корень, назначение: назначение)
        if let ожидаемый = итог.итоговыйИндексSHA256, текущийSHA != ожидаемый {
            if try шагУжеПрименён(шаг, номер: номер, корень: корень, точка: итог) {
                итог.следующийШаг = номер + 1
                итог.итоговыйИндексSHA256 = текущийSHA
                итог.итоговыеОтпечаткиКорней = try отпечаткиКорней(корень: корень, назначение: назначение)
                try await сохранить(итог, фаза: .подтверждённыйШаг, callback: callback)
                return итог
            }
            throw ОшибкаНормализацииКорнейАгентов.условие("индекс-разошёлся-с-контрольной-точкой")
        }
        try await сохранить(итог, фаза: .намерение, callback: callback)
        let восстановитьПослеПереименования: Bool
        if шаг.вид == .обновлениеДокумента {
            восстановитьПослеПереименования = try документОжидаетСтадирования(
                шаг, точка: итог, корень: корень)
        } else {
            восстановитьПослеПереименования = false
        }
        if восстановитьПослеПереименования {
            try проверитьНетНеучтённыхФайлов(корень: корень, назначение: назначение)
            try проверитьИзменёнТолькоДокумент(шаг, корень: корень, назначение: назначение)
            try stage(корень: корень, путь: шаг.целевойПуть)
            try проверитьСтадированныйДокумент(шаг, точка: итог, корень: корень)
        } else {
            try проверитьПредусловие(шаг, точка: итог, назначение: назначение, корень: корень)
            switch шаг.вид {
            case .переносФайла, .переносКаталога:
                _ = try git(корень, ["mv", "--", шаг.исходныйПуть, шаг.целевойПуть])
                try проверитьПеренос(шаг, корень: корень)
            case .удалениеДубликатаФайла:
                _ = try git(корень, ["rm", "--", шаг.исходныйПуть])
                try проверитьУдалениеИсточника(шаг, корень: корень)
            case .удалениеДубликатаКаталога:
                _ = try git(корень, ["rm", "-r", "--", шаг.исходныйПуть])
                try проверитьУдалениеИсточника(шаг, корень: корень)
            case .конфликтСохранён:
                try проверитьКонфликтСохранён(шаг, корень: корень)
            case .обновлениеДокумента:
                try обновитьДокумент(шаг, номер: номер, точка: итог, корень: корень)
            }
        }
        итог.следующийШаг = номер + 1
        итог.фаза = .применение
        итог.итоговыйИндексSHA256 = try индексSHA(корень: корень, назначение: назначение)
        итог.итоговыеОтпечаткиКорней = try отпечаткиКорней(корень: корень, назначение: назначение)
        try await сохранить(итог, фаза: .подтверждённыйШаг, callback: callback)
        return итог
    }

    private static func проверитьПредусловие(
        _ шаг: ШагНормализацииКорняАгента,
        точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        назначение: НазначениеНормализацииКорнейАгентов,
        корень: URL
    ) throws {
        try проверитьНетНеучтённыхИРабочихИзменений(корень: корень, назначение: назначение)
        if шаг.вид == .обновлениеДокумента {
            let текущий = try СистемаФайловНормализации.прочитать(корень: корень, путь: шаг.целевойПуть, предел: 4_194_304)
            guard let целевойSHA = точка.целевыеSHA256Документов[шаг.целевойПуть] else {
                throw ОшибкаНормализацииКорнейАгентов.условие("нет-хэша-документа")
            }
            if хэш(текущий.байты) == целевойSHA { return }
            guard let исходный = точка.документыСсылок.first(where: { $0.путь == шаг.исходныйПуть }),
                  хэш(текущий.байты) == исходный.sha256,
                  текущий.отпечаток == шаг.исходныйОтпечаток else {
                throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-документа-перед-перезаписью")
            }
            return
        }
        let источник = try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.исходныйПуть)
        guard источник == шаг.исходныйОтпечаток else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-источника-шага")
        }
        if шаг.вид == .переносФайла || шаг.вид == .переносКаталога {
            guard try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.целевойПуть) == nil else {
                throw ОшибкаНормализацииКорнейАгентов.условие("занята-цель-шага")
            }
            guard try индексныйОбъект(корень: корень, путь: шаг.исходныйПуть) == шаг.исходныйОбъект,
                  try индексныйОбъект(корень: корень, путь: шаг.целевойПуть) == nil else {
                throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-индекса-переноса")
            }
        } else if шаг.вид == .удалениеДубликатаФайла || шаг.вид == .удалениеДубликатаКаталога || шаг.вид == .конфликтСохранён {
            guard try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.целевойПуть) == шаг.целевойОтпечаток else {
                throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-цели-шага")
            }
            guard try индексныйОбъект(корень: корень, путь: шаг.исходныйПуть) == шаг.исходныйОбъект,
                  try индексныйОбъект(корень: корень, путь: шаг.целевойПуть) == шаг.целевойОбъект else {
                throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-индекса-дубликата-или-конфликта")
            }
        }
    }

    private static func документОжидаетСтадирования(
        _ шаг: ШагНормализацииКорняАгента,
        точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        корень: URL
    ) throws -> Bool {
        guard шаг.вид == .обновлениеДокумента,
              let ожидаемыйSHA = точка.целевыеSHA256Документов[шаг.целевойПуть],
              let объект = шаг.целевойОбъект,
              let режим = шаг.целевойРежим else { return false }
        let текущее = try СистемаФайловНормализации.прочитать(
            корень: корень, путь: шаг.целевойПуть, предел: 4_194_304)
        guard хэш(текущее.байты) == ожидаемыйSHA else { return false }
        guard let запись = try индекснаяЗаписьФайла(корень: корень, путь: шаг.целевойПуть),
              запись.объект == шаг.исходныйОбъект,
              запись.режим == шаг.исходныйРежим,
              режим == шаг.исходныйРежим else {
            throw ОшибкаНормализацииКорнейАгентов.условие("постобраз-документа-не-связан-с-ожиданием-индекса")
        }
        if объект == шаг.исходныйОбъект, режим == шаг.исходныйРежим {
            return false
        }
        guard объект.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неверный-целевой-Git-объект-документа")
        }
        return true
    }

    private static func проверитьИзменёнТолькоДокумент(
        _ шаг: ШагНормализацииКорняАгента,
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов
    ) throws {
        let пути = [назначение.владение.исходныйКорень, назначение.владение.целевойКорень]
        let данные = try git(корень, ["diff-files", "--name-only", "-z", "--"] + пути)
        let имена = try данные.split(separator: 0).map { запись -> String in
            guard let имя = String(data: Data(запись), encoding: .utf8) else {
                throw ОшибкаНормализацииКорнейАгентов.условие("не-UTF8-путь-из-diff-files")
            }
            return имя
        }
        guard имена == [шаг.целевойПуть] else {
            throw ОшибкаНормализацииКорнейАгентов.условие("изменён-не-только-переименованный-документ")
        }
    }

    private static func проверитьСтадированныйДокумент(
        _ шаг: ШагНормализацииКорняАгента,
        точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        корень: URL
    ) throws {
        guard let ожидаемыйSHA = точка.целевыеSHA256Документов[шаг.целевойПуть],
              let ожидаемыйОбъект = шаг.целевойОбъект,
              let ожидаемыйРежим = шаг.целевойРежим else {
            throw ОшибкаНормализацииКорнейАгентов.условие("нет-полного-ожидания-документа")
        }
        let файл = try СистемаФайловНормализации.прочитать(
            корень: корень, путь: шаг.целевойПуть, предел: 4_194_304)
        guard хэш(файл.байты) == ожидаемыйSHA,
              let запись = try индекснаяЗаписьФайла(корень: корень, путь: шаг.целевойПуть),
              запись.объект == ожидаемыйОбъект,
              запись.режим == ожидаемыйРежим else {
            throw ОшибкаНормализацииКорнейАгентов.условие("постобраз-документа-не-стадирован-точно")
        }
    }

    private static func проверитьПеренос(
        _ шаг: ШагНормализацииКорняАгента,
        корень: URL
    ) throws {
        guard try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.исходныйПуть) == nil,
              let после = try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.целевойПуть),
              после == шаг.исходныйОтпечаток,
              try индексныйОбъект(корень: корень, путь: шаг.целевойПуть) == шаг.исходныйОбъект else {
            throw ОшибкаНормализацииКорнейАгентов.условие("перенос-не-подтверждён")
        }
    }

    private static func проверитьУдалениеИсточника(
        _ шаг: ШагНормализацииКорняАгента,
        корень: URL
    ) throws {
        guard try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.исходныйПуть) == nil,
              try индексныйОбъект(корень: корень, путь: шаг.исходныйПуть) == nil,
              try индексныйОбъект(корень: корень, путь: шаг.целевойПуть) == шаг.целевойОбъект else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дедупликация-не-подтверждена")
        }
    }

    private static func проверитьКонфликтСохранён(
        _ шаг: ШагНормализацииКорняАгента,
        корень: URL
    ) throws {
        guard try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.исходныйПуть) == шаг.исходныйОтпечаток,
              try индексныйОбъект(корень: корень, путь: шаг.исходныйПуть) == шаг.исходныйОбъект else {
            throw ОшибкаНормализацииКорнейАгентов.условие("конфликтный-источник-изменён")
        }
        if let целевойОтпечаток = шаг.целевойОтпечаток {
            guard try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.целевойПуть) == целевойОтпечаток,
                  try индексныйОбъект(корень: корень, путь: шаг.целевойПуть) == шаг.целевойОбъект else {
                throw ОшибкаНормализацииКорнейАгентов.условие("конфликтная-цель-изменена")
            }
        }
    }

    private static func обновитьДокумент(
        _ шаг: ШагНормализацииКорняАгента,
        номер: Int,
        точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        корень: URL
    ) throws {
        let текущий = try СистемаФайловНормализации.прочитать(корень: корень, путь: шаг.целевойПуть, предел: 4_194_304)
        guard let ожидаемыйSHA = точка.целевыеSHA256Документов[шаг.целевойПуть] else {
            throw ОшибкаНормализацииКорнейАгентов.условие("нет-конечного-хэша-документа")
        }
        let shaТекущий = хэш(текущий.байты)
        if shaТекущий == ожидаемыйSHA {
            guard let ожидаемыйОбъект = шаг.целевойОбъект,
                  let ожидаемыйРежим = шаг.целевойРежим,
                  let запись = try индекснаяЗаписьФайла(корень: корень, путь: шаг.целевойПуть) else {
                throw ОшибкаНормализацииКорнейАгентов.условие("нет-индексной-записи-целевого-документа")
            }
            if запись.объект == ожидаемыйОбъект, запись.режим == ожидаемыйРежим {
                try проверитьСтадированныйДокумент(шаг, точка: точка, корень: корень)
                return
            }
            try stage(корень: корень, путь: шаг.целевойПуть)
            try проверитьСтадированныйДокумент(шаг, точка: точка, корень: корень)
            return
        }
        guard shaТекущий == точка.документыСсылок.first(where: { $0.путь == шаг.исходныйПуть })?.sha256,
              текущий.отпечаток == шаг.исходныйОтпечаток else {
            throw ОшибкаНормализацииКорнейАгентов.условие("документ-изменён-до-перезаписи")
        }
        let целевыеБайты = try вычислитьЦелевыеБайтыДокумента(шаг, точка: точка, корень: корень)
        guard хэш(целевыеБайты) == ожидаемыйSHA else {
            throw ОшибкаНормализацииКорнейАгентов.условие("не-воспроизведён-хэш-целевого-документа")
        }
        try СистемаФайловНормализации.записатьАтомарно(
            целевыеБайты,
            корень: корень,
            путь: шаг.целевойПуть,
            режим: текущий.режим,
            operationID: точка.operationID,
            номерШага: номер)
        try stage(корень: корень, путь: шаг.целевойПуть)
        try проверитьСтадированныйДокумент(шаг, точка: точка, корень: корень)
    }

    private static func вычислитьЦелевыеБайтыДокумента(
        _ шаг: ШагНормализацииКорняАгента,
        точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        корень: URL
    ) throws -> Data {
        let документ = try СистемаФайловНормализации.прочитать(корень: корень, путь: шаг.целевойПуть, предел: 4_194_304)
        guard let исходный = точка.документыСсылок.first(where: { $0.путь == шаг.исходныйПуть }) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неизвестен-исходный-документ")
        }
        if хэш(документ.байты) == исходный.sha256 { return НормализацияСсылок.переписать(документ.байты, шаги: точка.шаги) }
        // При возобновлении файл уже мог получить целевые байты, но остаться unstaged.
        return документ.байты
    }

    private static func шагУжеПрименён(
        _ шаг: ШагНормализацииКорняАгента,
        номер: Int,
        корень: URL,
        точка: КонтрольнаяТочкаНормализацииКорнейАгентов
    ) throws -> Bool {
        switch шаг.вид {
        case .переносФайла, .переносКаталога:
            guard try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.исходныйПуть) == nil else { return false }
            guard let целевой = try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.целевойПуть),
                  let исходныйОтпечаток = шаг.исходныйОтпечаток else { return false }
            if естьПозднийДокументВПрименённомПрефиксе(шаг, номер: номер, точка: точка) {
                if шаг.вид == .переносКаталога {
                    return целевой.устройство == исходныйОтпечаток.устройство
                        && целевой.inode == исходныйОтпечаток.inode
                        && целевой.типИРежим == исходныйОтпечаток.типИРежим
                }
                return целевой.типИРежим == исходныйОтпечаток.типИРежим
            }
            return целевой == шаг.исходныйОтпечаток
                && (try индексныйОбъект(корень: корень, путь: шаг.целевойПуть)) == шаг.исходныйОбъект
        case .удалениеДубликатаФайла, .удалениеДубликатаКаталога:
            guard try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.исходныйПуть) == nil,
                  try индексныйОбъект(корень: корень, путь: шаг.исходныйПуть) == nil else { return false }
            if естьПозднийДокументВПрименённомПрефиксе(шаг, номер: номер, точка: точка) {
                guard let целевой = try СистемаФайловНормализации.отпечаток(корень: корень, путь: шаг.целевойПуть),
                      let прежняяЦель = шаг.целевойОтпечаток else { return false }
                if шаг.вид == .удалениеДубликатаКаталога {
                    return целевой.устройство == прежняяЦель.устройство
                        && целевой.inode == прежняяЦель.inode
                        && целевой.типИРежим == прежняяЦель.типИРежим
                }
                return целевой.типИРежим == прежняяЦель.типИРежим
            }
            return try индексныйОбъект(корень: корень, путь: шаг.целевойПуть) == шаг.целевойОбъект
        case .конфликтСохранён:
            try проверитьКонфликтСохранён(шаг, корень: корень)
            return true
        case .обновлениеДокумента:
            guard let ожидаемый = точка.целевыеSHA256Документов[шаг.целевойПуть],
                  let ожидаемыйОбъект = шаг.целевойОбъект,
                  let ожидаемыйРежим = шаг.целевойРежим,
                  let текущее = try? СистемаФайловНормализации.прочитать(корень: корень, путь: шаг.целевойПуть, предел: 4_194_304),
                  хэш(текущее.байты) == ожидаемый else { return false }
            guard let запись = try индекснаяЗаписьФайла(корень: корень, путь: шаг.целевойПуть) else { return false }
            return запись.объект == ожидаемыйОбъект && запись.режим == ожидаемыйРежим
        }
    }

    private static func естьПозднийДокументВПрименённомПрефиксе(
        _ шаг: ШагНормализацииКорняАгента,
        номер: Int,
        точка: КонтрольнаяТочкаНормализацииКорнейАгентов
    ) -> Bool {
        let конец = min(точка.следующийШаг, точка.шаги.count)
        guard номер + 1 < конец else { return false }
        let потомки = точка.шаги[(номер + 1)..<конец]
        let префикс = шаг.целевойПуть + "/"
        return потомки.contains { следующий in
            guard следующий.вид == .обновлениеДокумента else { return false }
            return следующий.целевойПуть == шаг.целевойПуть
                || следующий.целевойПуть.hasPrefix(префикс)
        }
    }

    private static func проверитьИдентичностьGit(
        _ назначение: НазначениеНормализацииКорнейАгентов,
        корень: URL
    ) throws {
        let снимок = назначение.снимок
        guard try текстГита(корень, ["rev-parse", "--show-toplevel"]) == корень.path,
              try текстГита(корень, ["rev-parse", "HEAD"]) == снимок.commit,
              try текстГита(корень, ["rev-parse", "HEAD^{tree}"]) == снимок.дерево,
              try текстГита(корень, ["symbolic-ref", "HEAD"]) == снимок.fullRefЗапуска,
              try текстГита(корень, ["config", "--get", "user.name"]) + " <"
                + текстГита(корень, ["config", "--get", "user.email"]) + ">" == снимок.владелецЗапуска else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-идентичности-в-ходе-операции")
        }
    }

    private static func проверитьКонечноеСостояние(
        _ точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов
    ) throws {
        try проверитьНетНеучтённыхИРабочихИзменений(корень: корень, назначение: назначение)
        guard try индексSHA(корень: корень, назначение: назначение) == точка.итоговыйИндексSHA256,
              try отпечаткиКорней(корень: корень, назначение: назначение) == точка.итоговыеОтпечаткиКорней else {
            throw ОшибкаНормализацииКорнейАгентов.условие("конечные-отпечатки-не-совпали")
        }
        for (путь, sha) in точка.целевыеSHA256Документов {
            let файл = try СистемаФайловНормализации.прочитать(корень: корень, путь: путь, предел: 4_194_304)
            let шаг = точка.шаги.first(where: { $0.вид == .обновлениеДокумента && $0.целевойПуть == путь })
            guard хэш(файл.байты) == sha,
                  let объект = try хэшТекущегоОбъекта(корень: корень, путь: путь),
                  объект == шаг?.целевойОбъект else {
                throw ОшибкаНормализацииКорнейАгентов.условие("конечный-документ-не-совпал")
            }
        }
    }

    private static func проверитьКороткийNOOP(
        _ точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов
    ) throws {
        try проверитьИдентичностьGit(назначение, корень: корень)
        guard точка.фаза == .завершено,
              точка.следующийШаг == точка.шаги.count,
              try индексSHA(корень: корень, назначение: назначение) == точка.итоговыйИндексSHA256,
              try СистемаФайловНормализации.отпечаток(корень: корень, путь: назначение.владение.исходныйКорень) == точка.итоговыеОтпечаткиКорней[назначение.владение.исходныйКорень],
              try СистемаФайловНормализации.отпечаток(корень: корень, путь: назначение.владение.целевойКорень) == точка.итоговыеОтпечаткиКорней[назначение.владение.целевойКорень] else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-краткого-noop")
        }
        for (путь, sha) in точка.целевыеSHA256Документов {
            let данные = try СистемаФайловНормализации.прочитать(корень: корень, путь: путь, предел: 4_194_304).байты
            guard хэш(данные) == sha else {
                throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-пин-документа-краткого-noop")
            }
        }
    }

    private static func неизвестныйИсход(
        _ исходная: КонтрольнаяТочкаНормализацииКорнейАгентов,
        сохранять: Bool,
        callback: @Sendable (
            КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
        ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
    ) async -> РезультатНормализацииКорнейАгентов {
        let точка = await неизвестнаяКонтрольнаяТочка(
            исходная,
            сохранять: сохранять,
            callback: callback)
        return .init(исход: .неизвестно, контрольнаяТочка: точка, изменённыеПути: [], конфликты: точка.конфликты)
    }

    private static func неизвестнаяКонтрольнаяТочка(
        _ исходная: КонтрольнаяТочкаНормализацииКорнейАгентов,
        сохранять: Bool,
        callback: @Sendable (
            КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
        ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
    ) async -> КонтрольнаяТочкаНормализацииКорнейАгентов {
        var точка = исходная
        точка.фаза = .неизвестно
        if сохранять {
            _ = try? await сохранитьИВернуть(точка, фаза: .неизвестно, callback: callback)
        }
        return точка
    }

    private static func сохранить(
        _ точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        фаза: КонтрольнаяТочкаНормализацииКорнейАгентов.ФазаНамерения,
        callback: @Sendable (
            КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
        ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
    ) async throws {
        _ = try await сохранитьИВернуть(точка, фаза: фаза, callback: callback)
    }

    private static func сохранитьИВернуть(
        _ точка: КонтрольнаяТочкаНормализацииКорнейАгентов,
        фаза: КонтрольнаяТочкаНормализацииКорнейАгентов.ФазаНамерения,
        callback: @Sendable (
            КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
        ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
    ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение {
        var сохраняемаяТочка = точка
        switch фаза {
        case .намерение:
            сохраняемаяТочка.фаза = .намерение
        case .подтверждённыйШаг:
            сохраняемаяТочка.фаза = .применение
        case .терминал:
            сохраняемаяТочка.фаза = .завершено
        case .неизвестно:
            сохраняемаяТочка.фаза = .неизвестно
        }
        let байты = try ПланировщикНормализацииКорнейАгентов.каноническиеБайты(сохраняемаяТочка)
        let намерение = КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение(
            operationID: точка.operationID,
            фаза: фаза,
            каноническиеБайты: байты,
            sha256: ПланировщикНормализацииКорнейАгентов.хэш(байты))
        let перечитанное: КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
        do {
            перечитанное = try await callback(намерение)
        } catch {
            throw ОшибкаПодтвержденияКонтрольнойТочки.неПодтверждено
        }
        guard перечитанное == намерение else {
            throw ОшибкаПодтвержденияКонтрольнойТочки.неПодтверждено
        }
        return перечитанное
    }

    private static func индексSHA(
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов
    ) throws -> String {
        let привязка = назначение.владение
        let данные = try git(корень, ["ls-files", "--stage", "-z", "--", привязка.исходныйКорень, привязка.целевойКорень])
        return хэш(данные)
    }

    private static func отпечаткиКорней(
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов
    ) throws -> [String: ОтпечатокФайловойСистемыНормализации] {
        let исходный = назначение.владение.исходныйКорень
        let целевой = назначение.владение.целевойКорень
        var итог: [String: ОтпечатокФайловойСистемыНормализации] = [:]
        if let значение = try СистемаФайловНормализации.отпечаток(корень: корень, путь: исходный) { итог[исходный] = значение }
        if let значение = try СистемаФайловНормализации.отпечаток(корень: корень, путь: целевой) { итог[целевой] = значение }
        return итог
    }

    private static func индексныйОбъект(корень: URL, путь: String) throws -> String? {
        let данные = try git(корень, ["ls-files", "--stage", "-z", "--", путь])
        guard !данные.isEmpty else { return nil }
        let записи = данные.split(separator: 0)
        let префикс = Data((путь + "/").utf8)
        for запись in записи {
            guard let таб = запись.firstIndex(of: 9),
                  let полныйПуть = String(data: Data(запись[запись.index(after: таб)...]), encoding: .utf8),
                  Data(полныйПуть.utf8) == Data(путь.utf8) || Data(полныйПуть.utf8).starts(with: префикс),
                  let заголовок = String(data: Data(запись[..<таб]), encoding: .utf8) else {
                throw ОшибкаНормализацииКорнейАгентов.условие("индекс-содержит-неожиданный-путь")
            }
            let поля = заголовок.split(separator: " ")
            guard поля.count == 3, поля[2] == "0" else {
                throw ОшибкаНормализацииКорнейАгентов.условие("неразрешённая-стадия-индекса")
            }
        }
        let объект = try текст(git(корень, ["rev-parse", ":" + путь]))
        guard объект.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неверный-Git-объект-индекса")
        }
        return объект
    }

    private static func индекснаяЗаписьФайла(
        корень: URL,
        путь: String
    ) throws -> (режим: String, объект: String)? {
        let данные = try git(корень, ["ls-files", "--stage", "-z", "--", путь])
        guard !данные.isEmpty else { return nil }
        let записи = данные.split(separator: 0)
        guard записи.count == 1,
              let таб = записи[0].firstIndex(of: 9),
              let индексныйПуть = String(data: Data(записи[0][записи[0].index(after: таб)...]), encoding: .utf8),
              Data(индексныйПуть.utf8) == Data(путь.utf8),
              let заголовок = String(data: Data(записи[0][..<таб]), encoding: .utf8) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неоднозначная-индексная-запись-файла")
        }
        let поля = заголовок.split(separator: " ")
        guard поля.count == 3,
              поля[0].range(of: #"\A(?:100644|100755|120000)\z"#, options: .regularExpression) != nil,
              поля[1].range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil,
              поля[2] == "0" else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неразрешённая-индексная-запись-файла")
        }
        return (режим: String(поля[0]), объект: String(поля[1]))
    }

    private static func хэшТекущегоОбъекта(корень: URL, путь: String) throws -> String? {
        guard let индексный = try индексныйОбъект(корень: корень, путь: путь) else { return nil }
        let данные = try git(корень, ["rev-parse", ":" + путь])
        let объект = try текст(данные)
        guard объект == индексный else {
            throw ОшибкаНормализацииКорнейАгентов.условие("индекс-не-совпал-с-Git-объектом")
        }
        return объект
    }

    private static func stage(корень: URL, путь: String) throws {
        _ = try git(корень, ["add", "--", путь])
    }

    private static func проверитьНетНеучтённыхИРабочихИзменений(
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов
    ) throws {
        let источник = назначение.владение.исходныйКорень
        let цель = назначение.владение.целевойКорень
        let diff = try ЧитательПутей.гит(
            корень,
            ["--no-replace-objects", "--literal-pathspecs", "diff-files", "--quiet", "--", источник, цель],
            коды: [0, 1]).1
        guard diff == 0 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("появились-неучтённые-или-рабочие-изменения")
        }
        try проверитьНетНеучтённыхФайлов(корень: корень, назначение: назначение)
    }

    private static func проверитьНетНеучтённыхФайлов(
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов
    ) throws {
        let пути = [назначение.владение.исходныйКорень, назначение.владение.целевойКорень]
        let обычные = try git(корень, ["ls-files", "--others", "--exclude-standard", "-z", "--"] + пути)
        let игнорируемые = try git(корень, ["ls-files", "--others", "--ignored", "--exclude-standard", "-z", "--"] + пути)
        guard обычные.isEmpty, игнорируемые.isEmpty else {
            throw ОшибкаНормализацииКорнейАгентов.условие("появились-неучтённые-или-игнорируемые-файлы")
        }
    }

    private static func текстГита(_ корень: URL, _ аргументы: [String]) throws -> String {
        let данные = try git(корень, аргументы)
        return try текст(данные)
    }

    private static func текст(_ данные: Data) throws -> String {
        guard let значение = String(data: данные, encoding: .utf8) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("не-UTF8-ответ-Git")
        }
        return значение.trimmingCharacters(in: .newlines)
    }

    private static func git(_ корень: URL, _ аргументы: [String]) throws -> Data {
        try ЧитательПутей.гит(
            корень,
            ["--no-replace-objects", "--literal-pathspecs"] + аргументы).0
    }

    private static func хэш(_ данные: Data) -> String {
        SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
    }

    private static func порядок(_ левый: String, _ правый: String) -> Bool {
        левый.utf8.lexicographicallyPrecedes(правый.utf8)
    }

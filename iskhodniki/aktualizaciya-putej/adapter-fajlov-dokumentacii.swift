enum ПримитивыДокументации {
    static func требовать(_ условие: Bool, _ причина: String) throws {
        guard условие else { throw ОтказАдаптераДокументации.условие(причина) }
    }
    static func гит(_ корень: URL, _ аргументы: [String]) throws -> Data {
        try ПереименованиеФайла.гит(корень, аргументы)
    }
    static func текстГит(_ корень: URL, _ аргументы: [String]) throws -> String {
        let данные = try гит(корень, аргументы)
        guard let текст = String(data: данные, encoding: .utf8) else { throw ОтказАдаптераДокументации.условие("не-UTF8-Git") }
        return текст.trimmingCharacters(in: .newlines)
    }
    static func есть(_ адрес: URL) throws -> Bool {
        var сведения = stat()
        if lstat(адрес.path, &сведения) == 0 { return true }
        try требовать(errno == ENOENT, "не-проверено-отсутствие: " + адрес.path)
        return false
    }
    // Единственный canonically-equivalent физический spelling допускается;
    // неоднозначные NFC/case siblings и любой symlink закрываются.
    static func адрес(_ корень: URL, _ путь: String, отсутствующий: Bool = false) throws -> URL {
        try ИменаПутей.проверитьПуть(путь)
        var адрес = корень
        let части = ИменаПутей.компоненты(путь)
        for (номер, часть) in части.enumerated() {
            let имена = try FileManager.default.contentsOfDirectory(atPath: адрес.path)
            let совпадения = имена.filter { ИменаПутей.ключКоллизии($0) == ИменаПутей.ключКоллизии(часть) }
            if совпадения.isEmpty, отсутствующий, номер == части.count - 1 { return адрес.appendingPathComponent(часть) }
            try требовать(совпадения.count == 1, "нет-точного-единственного-компонента: " + путь)
            let имя = совпадения[0]
            try требовать(Data(имя.precomposedStringWithCanonicalMapping.utf8) == Data(часть.precomposedStringWithCanonicalMapping.utf8), "case-alias: " + путь)
            адрес.appendPathComponent(имя)
            let сведения = try СостояниеФайлаПереименования(адрес)
            try требовать(!сведения.ссылка && (номер == части.count - 1 || сведения.каталог), "небезопасный-компонент: " + путь)
        }
        return адрес
    }
    static func абсолютныйКаталог(_ адрес: URL, приватный: Bool = false) throws {
        try требовать(адрес.path == адрес.standardizedFileURL.path && адрес.path == адрес.resolvingSymlinksInPath().path, "нужен-физический-каталог")
        var текущий = URL(fileURLWithPath: "/")
        for часть in адрес.pathComponents.dropFirst() {
            текущий.appendPathComponent(часть)
            var сведения = stat()
            try требовать(lstat(текущий.path, &сведения) == 0 && сведения.st_mode & S_IFMT == S_IFDIR, "symlink-или-нет-каталога")
        }
        if приватный {
            var сведения = stat(); try требовать(lstat(адрес.path, &сведения) == 0 && сведения.st_uid == getuid()
                && сведения.st_mode & 0o7777 == 0o700, "нужен-собственный-приватный-каталог-0700")
        }
    }
    static func прочитать(_ адрес: URL, предел: Int, приватный: Bool = false) throws -> (Data, UInt32) {
        var до = stat()
        try требовать(lstat(адрес.path, &до) == 0 && до.st_mode & S_IFMT == S_IFREG && до.st_nlink == 1
            && до.st_uid == getuid() && до.st_size >= 0 && до.st_size <= предел, "небезопасный-или-большой-файл: " + адрес.path)
        if приватный { try требовать(до.st_mode & 0o7777 == 0o600, "не-приватный-файл") }
        let дескриптор = open(адрес.path, O_RDONLY | O_NOFOLLOW | O_CLOEXEC)
        try требовать(дескриптор >= 0, "не-открыт-файл"); defer { close(дескриптор) }
        var внутри = stat(); try требовать(fstat(дескриптор, &внутри) == 0 && внутри.st_ino == до.st_ino && внутри.st_dev == до.st_dev
            && внутри.st_mode == до.st_mode && внутри.st_size == до.st_size, "дрейф-до-чтения")
        var данные = Data(); var буфер = [UInt8](repeating: 0, count: 65_536)
        while true {
            let число = буфер.withUnsafeMutableBytes { Darwin.read(дескриптор, $0.baseAddress, min($0.count, предел - данные.count + 1)) }
            if число < 0 && errno == EINTR { continue }
            try требовать(число >= 0 && число <= предел - данные.count, "ошибка-или-рост-чтения")
            if число == 0 { break }; данные.append(contentsOf: буфер.prefix(число))
        }
        var после = stat(); var имя = stat()
        try требовать(fstat(дескриптор, &после) == 0 && lstat(адрес.path, &имя) == 0 && после.st_ino == внутри.st_ino
            && имя.st_ino == внутри.st_ino && имя.st_dev == внутри.st_dev && после.st_size == внутри.st_size
            && после.st_mode == внутри.st_mode && после.st_mtimespec.tv_sec == внутри.st_mtimespec.tv_sec
            && после.st_mtimespec.tv_nsec == внутри.st_mtimespec.tv_nsec && после.st_ctimespec.tv_sec == внутри.st_ctimespec.tv_sec
            && после.st_ctimespec.tv_nsec == внутри.st_ctimespec.tv_nsec, "дрейф-чтения")
        return (данные, UInt32(до.st_mode & 0o7777))
    }
    static func синхронизировать(_ адрес: URL, каталог: Bool = false) throws {
        let дескриптор = open(адрес.path, O_RDONLY | O_NOFOLLOW | O_CLOEXEC | (каталог ? O_DIRECTORY : 0))
        try требовать(дескриптор >= 0, "не-открыт-fsync"); defer { close(дескриптор) }
        var исход: Int32
        repeat { исход = fsync(дескриптор) } while исход != 0 && errno == EINTR
        try требовать(исход == 0, "fsync-отказ")
    }
    static func записатьНовый(_ данные: Data, _ адрес: URL, режим: UInt32 = 0o600) throws {
        let дескриптор = open(адрес.path, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, mode_t(режим))
        try требовать(дескриптор >= 0, "не-создан-новый-файл"); defer { close(дескриптор) }
        try данные.withUnsafeBytes { буфер in
            var смещение = 0
            while смещение < буфер.count {
                let число = Darwin.write(дескриптор, буфер.baseAddress!.advanced(by: смещение), буфер.count - смещение)
                if число < 0 && errno == EINTR { continue }
                try требовать(число > 0, "неполная-запись"); смещение += число
            }
        }
        try требовать(fchmod(дескриптор, mode_t(режим)) == 0 && fsync(дескриптор) == 0, "не-подтверждена-запись")
        try синхронизировать(адрес.deletingLastPathComponent(), каталог: true)
    }
    static func объектGit(_ данные: Data) -> String {
        var хэш = Insecure.SHA1(); хэш.update(data: Data("blob \(данные.count)\0".utf8)); хэш.update(data: данные)
        return хэш.finalize().map { String(format: "%02x", $0) }.joined()
    }
    static func индекс(_ данные: Data) throws -> [Data: ЗаписьИндексаДокументации] {
        try требовать(данные.count <= 33_554_432 && (данные.isEmpty || данные.last == 0), "неполный-индекс-stage")
        var итог: [Data: ЗаписьИндексаДокументации] = [:]
        for запись in данные.split(separator: 0) {
            guard let таб = запись.firstIndex(of: 9), let путь = String(data: Data(запись[запись.index(after: таб)...]), encoding: .utf8) else {
                throw ОтказАдаптераДокументации.условие("неверный-индекс-stage")
            }
            try ИменаПутей.проверитьПуть(путь)
            let поля = String(decoding: запись[..<таб], as: UTF8.self).split(separator: " ")
            try требовать(поля.count == 3 && поля[2] == "0" && ["100644", "100755", "120000", "160000"].contains(String(поля[0]))
                && поля[1].count == 40 && поля[1].allSatisfy({ $0.isHexDigit }), "не-stage0-или-неверный-индекс")
            try требовать(итог.updateValue(.init(путь: путь, режим: String(поля[0]), объект: String(поля[1])), forKey: Data(путь.utf8)) == nil, "дубликат-индекса")
        }
        return итог
    }
    static func состояние(_ корень: URL, _ путь: String) throws -> ОжиданиеУзлаДокументации {
        let адрес = try адрес(корень, путь)
        var сведения = stat(); try требовать(lstat(адрес.path, &сведения) == 0 && сведения.st_uid == getuid(), "не-свой-узел")
        if сведения.st_mode & S_IFMT == S_IFDIR { return .init(путь: путь, вид: "каталог", режим: "040000") }
        let данные = try прочитать(адрес, предел: 8_388_608).0
        return .init(путь: путь, вид: "файл", режим: сведения.st_mode & 0o111 == 0 ? "100644" : "100755", sha256: хэшПутей(данные))
    }
    static func снимокСостава(_ корень: URL) throws -> ([String: ОжиданиеУзлаДокументации], [String: Data], [String: UInt32]) {
        var итог: [String: ОжиданиеУзлаДокументации] = [:]
        var байты: [String: Data] = [:], режимы: [String: UInt32] = [:]
        func обход(_ путь: String) throws {
            try требовать(итог.count < 8192, "предел-состава-Docs")
            let физическийАдрес = try адрес(корень, путь)
            var сведения = stat(); try требовать(lstat(физическийАдрес.path, &сведения) == 0 && сведения.st_uid == getuid(), "не-свой-узел-состава")
            let узел: ОжиданиеУзлаДокументации
            if сведения.st_mode & S_IFMT == S_IFDIR {
                узел = .init(путь: путь, вид: "каталог", режим: "040000"); режимы[путь] = UInt32(сведения.st_mode & 0o7777)
            } else {
                let прочитанное = try прочитать(физическийАдрес, предел: 8_388_608)
                байты[путь] = прочитанное.0; режимы[путь] = прочитанное.1
                узел = .init(путь: путь, вид: "файл", режим: сведения.st_mode & 0o111 == 0 ? "100644" : "100755", sha256: хэшПутей(прочитанное.0))
            }
            итог[путь] = узел
            if узел.вид == "каталог" {
                let адрес = try адрес(корень, путь)
                let имена = try FileManager.default.contentsOfDirectory(atPath: адрес.path)
                var алиасы: Set<Data> = []
                for имя in имена.sorted(by: порядокПутей) {
                    try требовать(алиасы.insert(ИменаПутей.ключКоллизии(имя)).inserted, "case-NFC-коллизия-в-составе")
                    try обход(путь + "/" + имя.precomposedStringWithCanonicalMapping)
                }
            }
        }
        for кореньИмени in ["Документация", "dokumentaciya"] {
            let имена = try FileManager.default.contentsOfDirectory(atPath: корень.path)
            let кандидаты = имена.filter { ИменаПутей.ключКоллизии($0) == ИменаПутей.ключКоллизии(кореньИмени) }
            if !кандидаты.isEmpty { try требовать(кандидаты.count == 1, "алиас-корня-Docs"); try обход(кореньИмени) }
        }
        return (итог, байты, режимы)
    }
    static func состав(_ корень: URL) throws -> [String: ОжиданиеУзлаДокументации] { try снимокСостава(корень).0 }
    static func пространство(_ корень: URL, индекс: Data, узлыDocs: [String]) throws -> Set<Data> {
        var итог = Set(try self.индекс(индекс).keys)
        let новые = try гит(корень, ["ls-files", "--others", "--exclude-standard", "-z"])
        try требовать(новые.count <= 33_554_432, "предел-namespace-others")
        let путиДокументации = Dictionary(uniqueKeysWithValues: узлыDocs.map { (Data($0.precomposedStringWithCanonicalMapping.utf8), $0) })
        for сырая in новые.split(separator: 0) {
            guard var путь = String(data: Data(сырая), encoding: .utf8) else { throw ОтказАдаптераДокументации.условие("не-UTF8-namespace") }
            try ИменаПутей.проверитьПуть(путь)
            if let логический = путиДокументации[Data(путь.precomposedStringWithCanonicalMapping.utf8)] { путь = логический }
            итог.insert(Data(путь.utf8))
        }
        for путь in узлыDocs { итог.insert(Data(путь.utf8)) }
        for ключ in Array(итог) {
            var родитель = (String(decoding: ключ, as: UTF8.self) as NSString).deletingLastPathComponent
            while !родитель.isEmpty { итог.insert(Data(родитель.utf8)); родитель = (родитель as NSString).deletingLastPathComponent }
        }
        try требовать(итог.count <= 200_000, "предел-полного-пространства")
        return итог
    }
}

// Конкретный adapter существующего core. Ничего не запускается при импорте.
// Полномочие и текущий пакет передаются явно; собственного Root/таймера нет.
final class СистемныеЭффектыДокументации: ЭффектыКонечногоПакетаДокументации {
    let пакет: ПакетИсполненияДокументации
    private let допуск: ДопускИсполненияДокументации
    private let корень: URL
    private let каталогGit: URL
    private let адресИндекса: URL
    private let хэшПлана: String
    private var префикс = 0
    private var индексы: [Int: String]
    private var подготовленные: [Int: РезервШагаДокументации] = [:]
    private var временныйФайл: (путь: String, данные: Data, режим: UInt32)?
    weak var журнал: СегментныйЖурналДокументации?
    var неисправность: ((String, Int) throws -> Void)?
    private(set) var начатоПримитивов = 0

    init(пакет: ПакетИсполненияДокументации, допуск: ДопускИсполненияДокументации) throws {
        self.пакет = пакет; self.допуск = допуск
        корень = URL(fileURLWithPath: пакет.корень); каталогGit = URL(fileURLWithPath: пакет.каталогGit)
        адресИндекса = каталогGit.appendingPathComponent("index")
        хэшПлана = try хэшПутей(байтыПлана(пакет.план)); индексы = [0: хэшПутей(пакет.физическийИндексДо)]
        try ПримитивыДокументации.требовать(допуск.пакетSHA256 == хэшПутей(байтыПлана(пакет))
            && допуск.физическийКорень == пакет.корень && допуск.ветка == пакет.план.основа.ветка
            && допуск.коммит == пакет.план.основа.коммит && !допуск.источникРешения.isEmpty
            && !допуск.входящийОхватИГраницыРесурсов.isEmpty && допуск.удалениеИсходниковРазрешено, "нет-точного-допуска-на-файловые-эффекты")
        try ПримитивыДокументации.абсолютныйКаталог(корень)
        try ПримитивыДокументации.абсолютныйКаталог(каталогGit)
        try ПримитивыДокументации.требовать(try ПримитивыДокументации.текстГит(корень, ["rev-parse", "--show-toplevel"]) == пакет.корень
            && ПримитивыДокументации.текстГит(корень, ["rev-parse", "--path-format=absolute", "--git-dir"]) == пакет.каталогGit, "другой-worktree-или-index-root")
        for правка in пакет.план.внешниеПравки {
            try ПримитивыДокументации.требовать(допуск.внешниеПодтверждения[правка.путь] == правка.будущийSHA256, "нет-подтверждения-внешнего-владельца: " + правка.путь)
        }
        var проверенные: [ДоказательствоКопииДокументации] = []
        let поПути = Dictionary(uniqueKeysWithValues: пакет.план.исходныеУзлы.map { (Data($0.путь.utf8), $0) })
        for шаг in пакет.план.шаги where шаг.действие == .схлопнутьКопию {
            guard let имя = шаг.исходный, let исходный = поПути[Data(имя.utf8)], let целевой = поПути[Data(шаг.целевой.utf8)] else {
                throw ОтказАдаптераДокументации.условие("нет-точной-пары-доказательство-gate")
            }
            if имя == "Документация/README.md" {
                try ПримитивыДокументации.требовать(пакет.план.слияниеREADME != nil, "нет-решения-README"); continue
            }
            if (имя as NSString).pathExtension.lowercased() == "md" {
                проверенные.append(try ДоказательствоАдреснойКопииДокументации.построить(исходный: исходный, целевой: целевой,
                    отображения: пакет.план.отображения, пространство: Set(пакет.план.исходноеПространство)))
            } else { try ПримитивыДокументации.требовать(исходный.байты == целевой.байты && исходный.режим == целевой.режим, "разный-nonMD-dedup") }
        }
        try ПримитивыДокументации.требовать(проверенные.sorted { порядокПутей($0.исходный, $1.исходный) } == пакет.доказательстваКопий,
            "не-полная-bijection-доказательство-и-coalesce")
    }
    private func ожидаемое(_ номер: Int) throws -> ([String: ОжиданиеУзлаДокументации], [String: UInt32], [Data: ЗаписьИндексаДокументации]) {
        var узлы = Dictionary(uniqueKeysWithValues: пакет.план.исходныеУзлы.map {
            ($0.путь, ОжиданиеУзлаДокументации(путь: $0.путь, вид: $0.вид.rawValue, режим: $0.режим,
                sha256: $0.вид == .файл ? хэшПутей($0.байты) : nil))
        })
        var режимы = пакет.режимыУзлов
        var индекс = try ПримитивыДокументации.индекс(пакет.план.индексДо)
        var содержимое = Dictionary(uniqueKeysWithValues: пакет.план.исходныеУзлы.filter { $0.вид == .файл }.map { (Data($0.путь.utf8), $0.байты) })
        for шаг in пакет.план.шаги.prefix(номер) {
            switch шаг.действие {
            case .перенестиФайл:
                guard let исходный = шаг.исходный, var запись = индекс.removeValue(forKey: Data(исходный.utf8)),
                      let байты = содержимое.removeValue(forKey: Data(исходный.utf8)), let режим = режимы.removeValue(forKey: исходный) else {
                    throw ОтказАдаптераДокументации.условие("не-отслеживаемый-источник-MOVE")
                }
                запись.путь = шаг.целевой; индекс[Data(шаг.целевой.utf8)] = запись
                содержимое[Data(шаг.целевой.utf8)] = байты; режимы[шаг.целевой] = режим
            case .заменитьБайты:
                guard let байты = шаг.байтыПосле else { throw ОтказАдаптераДокументации.условие("нет-payload") }
                содержимое[Data(шаг.целевой.utf8)] = байты // Рабочие bytes, не слепой git add.
            case .схлопнутьКопию:
                guard let исходный = шаг.исходный, индекс[Data(исходный.utf8)] != nil,
                      let байты = содержимое[Data(шаг.целевой.utf8)], let цель = шаг.после.first(where: { $0.путь == шаг.целевой }) else {
                    throw ОтказАдаптераДокументации.условие("неполная-пара-схлопывания")
                }
                if индекс[Data(шаг.целевой.utf8)] == nil {
                    индекс[Data(шаг.целевой.utf8)] = .init(путь: шаг.целевой, режим: цель.режим ?? "", объект: ПримитивыДокументации.объектGit(байты))
                }
                индекс.removeValue(forKey: Data(исходный.utf8)); содержимое.removeValue(forKey: Data(исходный.utf8)); режимы.removeValue(forKey: исходный)
            case .создатьКаталог: режимы[шаг.целевой] = 0o755
            case .удалитьПустойКаталог: режимы.removeValue(forKey: шаг.целевой)
            }
            for после in шаг.после {
                if после.вид == "отсутствует" { узлы.removeValue(forKey: после.путь) }
                else { узлы[после.путь] = после }
            }
        }
        return (узлы, режимы, индекс)
    }
    private func нормализовать(_ узлы: [String: ОжиданиеУзлаДокументации]) throws -> [Data: ОжиданиеУзлаДокументации] {
        var итог: [Data: ОжиданиеУзлаДокументации] = [:]
        for (имя, var узел) in узлы {
            узел.путь = имя.precomposedStringWithCanonicalMapping
            try ПримитивыДокументации.требовать(итог.updateValue(узел, forKey: Data(узел.путь.utf8)) == nil, "NFC-алиас-в-ожидании")
        }
        return итог
    }
    func сверить(_ план: ПланПакетаДокументации, префикс номер: Int) throws {
        try ПримитивыДокументации.требовать(try байтыПлана(план) == байтыПлана(пакет.план)
            && (0...план.шаги.count).contains(номер), "другой-план-или-prefix")
        try ПримитивыДокументации.абсолютныйКаталог(корень)
        try ПримитивыДокументации.требовать(try ПримитивыДокументации.текстГит(корень, ["rev-parse", "HEAD"]) == план.основа.коммит
            && ПримитивыДокументации.текстГит(корень, ["symbolic-ref", "HEAD"]) == план.основа.ветка
            && ПримитивыДокументации.текстГит(корень, ["rev-parse", "HEAD^{tree}"]) == план.основа.дерево
            && !ПримитивыДокументации.есть(каталогGit.appendingPathComponent("index.lock")), "дрейф-Git-или-index.lock")
        let ожидание = try ожидаемое(номер)
        let логическийИндекс = try ПримитивыДокументации.гит(корень, ["ls-files", "--stage", "-z"])
        let фактическийИндекс = try ПримитивыДокументации.индекс(логическийИндекс)
        try ПримитивыДокументации.требовать(фактическийИндекс == ожидание.2, "изменён-логический-индекс")
        let физический = try ПримитивыДокументации.прочитать(адресИндекса, предел: 67_108_864)
        let ожидаемыйХэш = индексы[номер] ?? журнал?.индексы[номер]?.индексSHA256
        try ПримитивыДокументации.требовать(ожидаемыйХэш == хэшПутей(физический.0) && физический.1 == пакет.режимИндекса, "дрейф-физического-индекса")
        var состав = try ПримитивыДокументации.состав(корень)
        if let временныйФайл {
            let ключ = временныйФайл.путь.precomposedStringWithCanonicalMapping
            guard let узел = состав.removeValue(forKey: ключ) else { throw ОтказАдаптераДокументации.условие("потерян-own-temp") }
            let адрес = try ПримитивыДокументации.адрес(корень, временныйФайл.путь)
            let прочитанное = try ПримитивыДокументации.прочитать(адрес, предел: 8_388_608)
            try ПримитивыДокументации.требовать(узел.вид == "файл" && прочитанное.0 == временныйФайл.данные
                && прочитанное.1 == временныйФайл.режим, "дрейф-own-temp")
        }
        try ПримитивыДокументации.требовать(try нормализовать(состав) == нормализовать(ожидание.0), "дрейф-полного-физического-состава-Docs")
        for (путь, режим) in ожидание.1 {
            let адрес = try ПримитивыДокументации.адрес(корень, путь)
            var сведения = stat(); try ПримитивыДокументации.требовать(lstat(адрес.path, &сведения) == 0
                && UInt32(сведения.st_mode & 0o7777) == режим, "дрейф-режима-узла")
        }
        var ожидаемоеПространство = Set(план.исходноеПространство.filter {
            let путь = String(decoding: $0, as: UTF8.self)
            return путь != "Документация" && путь != "dokumentaciya" && !путь.hasPrefix("Документация/") && !путь.hasPrefix("dokumentaciya/")
        })
        for путь in ожидание.0.keys { ожидаемоеПространство.insert(Data(путь.utf8)) }
        func сверитьПространство() throws {
            var фактическое = try ПримитивыДокументации.пространство(корень, индекс: логическийИндекс, узлыDocs: Array(ожидание.0.keys))
            if let временныйФайл {
                let точный = фактическое.filter { Data(String(decoding: $0, as: UTF8.self).precomposedStringWithCanonicalMapping.utf8)
                    == Data(временныйФайл.путь.precomposedStringWithCanonicalMapping.utf8) }
                try ПримитивыДокументации.требовать(точный.count == 1, "не-точный-temp-в-namespace")
                фактическое.subtract(точный)
            }
            try ПримитивыДокументации.требовать(фактическое == ожидаемоеПространство, "дрейф-полного-namespace-census")
        }
        try сверитьПространство()
        if номер == 0 || номер == план.шаги.count {
            for результат in план.нормализованные.values {
                for цель in результат.целиПосле {
                    let исходные = план.отображения.filter { Data($0.целевой.utf8) == Data(цель.utf8) }.map(\.исходный)
                    let кандидат = ([цель] + исходные).first { ожидание.0[$0] != nil }
                    _ = try ПримитивыДокументации.адрес(корень, кандидат ?? цель)
                }
            }
            try сверитьПространство()
            try ПримитивыДокументации.требовать(try ПримитивыДокументации.гит(корень, ["ls-files", "--stage", "-z"]) == логическийИндекс,
                "поздний-дрейф-индекса-после-namespace")
        }
        префикс = номер
    }
    private func подготовитьРезервы(_ шаг: ШагПакетаДокументации, индекс: Bool, файлРезерва: URL? = nil) throws {
        guard let журнал else { throw ОтказАдаптераДокументации.условие("нет-journal-lock") }
        var данные: [(РезервФайлаДокументации, Data)] = []
        func резерв(_ вид: String, _ адрес: URL) throws {
            let прочитанное = try ПримитивыДокументации.прочитать(адрес, предел: 67_108_864)
            let имя = вид + ".fum-p4-" + String(хэшПлана.prefix(16)) + "-\(шаг.номер).reserve"
            данные.append((.init(имя: имя, байт: прочитанное.0.count, sha256: хэшПутей(прочитанное.0), режим: прочитанное.1), прочитанное.0))
        }
        if индекс { try резерв("index", адресИндекса) }
        if let файлРезерва { try резерв("payload", файлРезерва) }
        let описание = РезервШагаДокументации(номер: шаг.номер, файлы: данные.map(\.0))
        try журнал.сохранитьРезерв(описание) // durable reserve-intent до создания файлов.
        for (файл, байты) in данные { try ПримитивыДокументации.записатьНовый(байты, каталогGit.appendingPathComponent(файл.имя)) }
        подготовленные[шаг.номер] = описание
    }
    private func синхронизироватьGit(_ родители: [URL]) throws {
        let дескриптор = open(адресИндекса.path, O_RDONLY | O_NOFOLLOW | O_CLOEXEC)
        try ПримитивыДокументации.требовать(дескриптор >= 0, "нет-индекса-после-Git"); defer { close(дескриптор) }
        try ПримитивыДокументации.требовать(fchmod(дескриптор, mode_t(пакет.режимИндекса)) == 0 && fsync(дескриптор) == 0, "не-подтверждён-индекс-Git")
        try ПримитивыДокументации.синхронизировать(каталогGit, каталог: true)
        for родитель in родители { try ПримитивыДокументации.синхронизировать(родитель, каталог: true) }
    }
    func выполнить(_ шаг: ШагПакетаДокументации) throws -> ИсходПримитиваДокументации {
        try ПримитивыДокументации.требовать(префикс < пакет.план.шаги.count && пакет.план.шаги[префикс] == шаг
            && журнал?.номерНамерения == шаг.номер && журнал?.подтверждённыйПрефикс == префикс, "примитив-без-точного-intent")
        try сверить(пакет.план, префикс: префикс)
        try неисправность?("до-примитива", шаг.номер)
        начатоПримитивов += 1
        switch шаг.действие {
        case .создатьКаталог:
            let адрес = try ПримитивыДокументации.адрес(корень, шаг.целевой, отсутствующий: true)
            try ПримитивыДокументации.требовать(mkdir(адрес.path, 0o755) == 0 && chmod(адрес.path, 0o755) == 0, "mkdir-отказ")
            try ПримитивыДокументации.синхронизировать(адрес, каталог: true)
            try ПримитивыДокументации.синхронизировать(адрес.deletingLastPathComponent(), каталог: true)
        case .перенестиФайл:
            guard let источник = шаг.исходный else { throw ОтказАдаптераДокументации.условие("нет-источника-MOVE") }
            let из = try ПримитивыДокументации.адрес(корень, источник), в = try ПримитивыДокументации.адрес(корень, шаг.целевой, отсутствующий: true)
            try подготовитьРезервы(шаг, индекс: true)
            try неисправность?("после-резервов", шаг.номер)
            try сверить(пакет.план, префикс: префикс)
            _ = try ПримитивыДокументации.гит(корень, ["mv", "--", источник, шаг.целевой])
            try ПримитивыДокументации.синхронизировать(в)
            try синхронизироватьGit([из.deletingLastPathComponent(), в.deletingLastPathComponent()])
        case .заменитьБайты:
            let адрес = try ПримитивыДокументации.адрес(корень, шаг.целевой)
            guard let байты = шаг.байтыПосле else { throw ОтказАдаптераДокументации.условие("нет-payload") }
            let режим = try ПримитивыДокументации.прочитать(адрес, предел: 8_388_608).1
            try подготовитьРезервы(шаг, индекс: false, файлРезерва: адрес)
            let временный = адрес.deletingLastPathComponent().appendingPathComponent(".fum-p4-" + String(хэшПлана.prefix(16)) + "-\(шаг.номер).tmp")
            try ПримитивыДокументации.записатьНовый(байты, временный, режим: режим)
            let родитель = (шаг.целевой as NSString).deletingLastPathComponent
            временныйФайл = (родитель + "/" + временный.lastPathComponent, байты, режим)
            try неисправность?("после-payload-fsync", шаг.номер)
            try сверить(пакет.план, префикс: префикс)
            try ПримитивыДокументации.требовать(rename(временный.path, адрес.path) == 0, "atomic-rename-отказ")
            временныйФайл = nil
            try ПримитивыДокументации.синхронизировать(адрес.deletingLastPathComponent(), каталог: true)
        case .схлопнутьКопию:
            guard let источник = шаг.исходный else { throw ОтказАдаптераДокументации.условие("нет-источника-dedup") }
            let из = try ПримитивыДокументации.адрес(корень, источник), в = try ПримитивыДокументации.адрес(корень, шаг.целевой)
            try подготовитьРезервы(шаг, индекс: true, файлРезерва: из)
            try неисправность?("после-резервов", шаг.номер)
            try сверить(пакет.план, префикс: префикс)
            let до = try ожидаемое(префикс).2
            if до[Data(шаг.целевой.utf8)] == nil {
                _ = try ПримитивыДокументации.гит(корень, ["add", "--", шаг.целевой])
                var промежуточный = try ожидаемое(шаг.номер).2
                промежуточный[Data(источник.utf8)] = до[Data(источник.utf8)]
                try ПримитивыДокументации.требовать(try ПримитивыДокументации.индекс(ПримитивыДокументации.гит(корень, ["ls-files", "--stage", "-z"])) == промежуточный, "неверный-index-после-prepared-add")
                try синхронизироватьGit([в.deletingLastPathComponent()])
                try неисправность?("после-prepared-add", шаг.номер)
                try ПримитивыДокументации.требовать(try ПримитивыДокументации.индекс(ПримитивыДокументации.гит(корень, ["ls-files", "--stage", "-z"])) == промежуточный
                    && ПримитивыДокументации.текстГит(корень, ["rev-parse", "HEAD"]) == пакет.план.основа.коммит
                    && ПримитивыДокументации.текстГит(корень, ["symbolic-ref", "HEAD"]) == пакет.план.основа.ветка, "дрейф-после-prepared-add")
                for до in шаг.до { try ПримитивыДокументации.требовать(try ПримитивыДокументации.состояние(корень, до.путь) == до, "дрейф-пары-перед-rm") }
            }
            _ = try ПримитивыДокументации.гит(корень, ["rm", "--", источник])
            try синхронизироватьGit([из.deletingLastPathComponent(), в.deletingLastPathComponent()])
        case .удалитьПустойКаталог:
            let адрес = try ПримитивыДокументации.адрес(корень, шаг.целевой)
            try ПримитивыДокументации.требовать(try FileManager.default.contentsOfDirectory(atPath: адрес.path).isEmpty, "каталог-не-пуст")
            try ПримитивыДокументации.требовать(rmdir(адрес.path) == 0, "rmdir-отказ")
            try ПримитивыДокументации.синхронизировать(адрес.deletingLastPathComponent(), каталог: true)
        }
        try неисправность?("после-примитива", шаг.номер)
        try ПримитивыДокументации.требовать(try ПримитивыДокументации.индекс(ПримитивыДокументации.гит(корень, ["ls-files", "--stage", "-z"])) == ожидаемое(шаг.номер).2, "неверный-post-index")
        индексы[шаг.номер] = try хэшПутей(ПримитивыДокументации.прочитать(адресИндекса, предел: 67_108_864).0)
        try сверить(пакет.план, префикс: шаг.номер)
        return .подтверждено
    }
    func свидетельство(_ номер: Int) throws -> СвидетельствоИндексаДокументации {
        try ПримитивыДокументации.требовать(префикс == номер && номер > 0, "нет-postimage-для-receipt")
        guard let хэш = индексы[номер] else { throw ОтказАдаптераДокументации.условие("нет-физического-index-pin") }
        return try .init(номер: номер, шагSHA256: хэшПутей(байтыПлана(пакет.план.шаги[номер - 1])), индексSHA256: хэш, режимИндекса: пакет.режимИндекса)
    }
    func очиститьРезервы(_ номер: Int) throws {
        try неисправность?("до-очистки-резервов", номер)
        guard let резерв = подготовленные[номер] else { return }
        for файл in резерв.файлы {
            let адрес = каталогGit.appendingPathComponent(файл.имя)
            let байты = try ПримитивыДокументации.прочитать(адрес, предел: 67_108_864, приватный: true).0
            try ПримитивыДокументации.требовать(байты.count == файл.байт && хэшПутей(байты) == файл.sha256, "дрейф-резерва-не-удалять")
            try ПримитивыДокументации.требовать(unlink(адрес.path) == 0, "не-удалён-подтверждённый-резерв")
        }
        try ПримитивыДокументации.синхронизировать(каталогGit, каталог: true); подготовленные.removeValue(forKey: номер)
    }

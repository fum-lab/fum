import Foundation

enum ИсходПримитиваДокументации: Equatable, Sendable { case подтверждено, неизвестно }
enum ИсходОбъединенияДокументации: String, Codable, Sendable { case завершено, удержано, неизвестно }
struct КвитанцияОбъединенияДокументации: Codable, Equatable, Sendable {
    var планSHA256: String
    var исход: ИсходОбъединенияДокументации
    var подтверждённыйПрефикс: Int
    var причина: String?
}
enum ОткрытиеПакетаДокументации: Sendable {
    case новый
    case завершённый(КвитанцияОбъединенияДокументации)
    case незавершённоеНамерение
    case удержанныйПрефикс(подтверждённый: Int, номерНамерения: Int?)
}

// Seam существующего журнала, не новый storage/queue. Реальный adapter обязан
// удерживать exclusive lock постоянного worktree-slot от open до terminal;
// append означает проверенный durable commit/fsync, а не запись в буфер.
// Marker/segment mismatch, хвост, другой planSHA и потеря store → отказ.
// NEW разрешён только при доказанно новом слоте; новый UUID не обходит intent.
protocol ЖурналКонечногоПакетаДокументации: AnyObject {
    func открыть(план: Data) throws -> ОткрытиеПакетаДокументации
    func намерение(_ шаг: ШагПакетаДокументации, хэшПлана: String) throws
    func подтверждение(_ шаг: ШагПакетаДокументации, хэшПлана: String) throws
    func очиститьПослеПодтверждения(_ шаг: ШагПакетаДокументации) throws
    func завершить(_ квитанция: КвитанцияОбъединенияДокументации) throws
    // Освободить lock/дескрипторы; намерение, резервы и неизвестный хвост оставить.
    func закрыть()
}
extension ЖурналКонечногоПакетаДокументации {
    func очиститьПослеПодтверждения(_ шаг: ШагПакетаДокументации) throws {}
}

// Seam файлового executor: не вызывается legacy fixed9 с чужим plan.
// сверить проверяет собственный W/ref/HEAD, exact index, весь census (включая
// untracked), no-follow parents/modes/bytes и состояние каждого шага на prefix.
// выполнить делает ровно один примитив: mkdir / git mv -- / atomic payload /
// proved coalescence с recoverable source+index. Никаких mv -f и overwrite
// занятой цели. Любой запущенный, но не доказанный эффект → неизвестно.
// Adapter заранее проверяет exact execution grant, sole writer, внешние owner
// receipts, бюджеты и recoverable reserves. Source-only этот adapter не даёт.
protocol ЭффектыКонечногоПакетаДокументации: AnyObject {
    func сверить(_ план: ПланПакетаДокументации, префикс: Int) throws
    func выполнить(_ шаг: ШагПакетаДокументации) throws -> ИсходПримитиваДокументации
}

enum ПрименениеОбъединенияДокументации {
    static func выполнить(_ план: ПланПакетаДокументации, ожидаемыйSHA256: String,
        журнал: any ЖурналКонечногоПакетаДокументации,
        среда: any ЭффектыКонечногоПакетаДокументации) throws -> КвитанцияОбъединенияДокументации {
        let байты = try байтыПлана(план), хэш = хэшПутей(байты)
        guard хэш == ожидаемыйSHA256, план.схема == "fum.профиль-объединения-документации.1",
              хэшПутей(план.индексДо) == план.основа.индексSHA256,
              план.шаги.count <= 32768,
              план.шаги.enumerated().allSatisfy({ $0.element.номер == $0.offset + 1 }) else {
            throw ОтказОбщейМиграции.условие("неверный-план-применения-Docs")
        }
        let пересчитанный = try ПрофильОбъединенияДокументации.построить(основа: план.основа, ожидаемаяОснова: план.основа,
            узлы: план.исходныеУзлы, пространство: Set(план.исходноеПространство), индексДо: план.индексДо,
            каноны: план.каноны, входящие: план.входящиеДо.map { .init(путь: $0.путь, байты: $0.байты, sha256: $0.sha256) },
            времяСвежести: план.времяСвежести, слияниеREADME: план.слияниеREADME)
        guard try байтыПлана(пересчитанный) == байты else { throw ОтказОбщейМиграции.условие("план-Docs-не-совпадает-с-повторным-вычислением") }
        func квитанция(_ исход: ИсходОбъединенияДокументации, _ префикс: Int, _ причина: String? = nil) -> КвитанцияОбъединенияДокументации {
            .init(планSHA256: хэш, исход: исход, подтверждённыйПрефикс: префикс, причина: причина)
        }
        guard план.препятствия.isEmpty else { return квитанция(.удержано, 0, "есть-препятствия-плана") }
        // Нулевой пакет не открывает новый slot/журнал и не создаёт receipt.
        guard !план.шаги.isEmpty else { return квитанция(.удержано, 0, "нет-эффектов-NOOP") }
        var префикс = 0
        do {
            defer { журнал.закрыть() }
            switch try журнал.открыть(план: байты) {
            case .незавершённоеНамерение:
                return квитанция(.удержано, 0, "сохранённое-намерение-без-исхода-не-повторено")
            case .удержанныйПрефикс(let известный, let намерение):
                guard (0...план.шаги.count).contains(известный),
                      намерение.map({ $0 == известный + 1 && $0 <= план.шаги.count }) ?? true else {
                    return квитанция(.удержано, 0, "неверный-retained-prefix")
                }
                return квитанция(.удержано, известный, намерение == nil
                    ? "сохранённый-префикс-без-terminal-не-продолжен"
                    : "сохранённое-намерение-на-шаге-\(намерение!)-не-повторено")
            case .завершённый(let сохранённая):
                guard сохранённая.планSHA256 == хэш, сохранённая.исход == .завершено,
                      сохранённая.подтверждённыйПрефикс == план.шаги.count, сохранённая.причина == nil else {
                    return квитанция(.удержано, 0, "неверный-сохранённый-исход")
                }
                // Сохранённая квитанция не заменяет проверку фактического postimage.
                try среда.сверить(план, префикс: план.шаги.count)
                return сохранённая
            case .новый: break
            }
            try среда.сверить(план, префикс: 0)
            for шаг in план.шаги {
                try среда.сверить(план, префикс: префикс)
                try журнал.намерение(шаг, хэшПлана: хэш)
                try среда.сверить(план, префикс: префикс)
                guard try среда.выполнить(шаг) == .подтверждено else {
                    return квитанция(.неизвестно, префикс, "примитив-не-подтверждён")
                }
                try среда.сверить(план, префикс: шаг.номер)
                try журнал.подтверждение(шаг, хэшПлана: хэш)
                префикс = шаг.номер
                try журнал.очиститьПослеПодтверждения(шаг)
            }
            try среда.сверить(план, префикс: префикс)
            let итог = квитанция(.завершено, префикс)
            try журнал.завершить(итог)
            return итог
        } catch {
            // Никакого повторного append, нового slot/UUID, слепого rollback или
            // повторного эффекта. Durable prefix мог отстать от фактической ФС.
            return квитанция(.неизвестно, префикс, String(describing: error))
        }
    }
}

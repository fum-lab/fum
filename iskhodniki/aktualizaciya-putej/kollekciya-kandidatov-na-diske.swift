struct ПровереннаяКоллекцияНаДиске: Sendable {
    let идентичностьКорня: String
    let хэшУчёта: String
    let хэшНаблюдений: String
    let файлы: Int
    let каталоги: Int
    let прочитаноБайтов: Int
    let физическиеФайлыПроверены = true
    let явноПустыеРасширенныеПраваПодтверждены = true
    let текущаяГоловаПроверена = false
    let внешняяИсторияПроверена = false
    let терминальныйПроцессПроверен = false
    let продолжениеРазрешено = false
    let применениеРазрешено = false
    fileprivate init(идентичностьКорня: String, хэшУчёта: String, хэшНаблюдений: String, файлы: Int, каталоги: Int, прочитаноБайтов: Int) {
        self.идентичностьКорня = идентичностьКорня; self.хэшУчёта = хэшУчёта; self.хэшНаблюдений = хэшНаблюдений
        self.файлы = файлы; self.каталоги = каталоги; self.прочитаноБайтов = прочитаноБайтов
    }
}
enum ПроверкаКоллекцииНаДиске {
    private static func требовать(_ условие: Bool, _ код: String) throws {
        if !условие { throw ОтказСсылокПакета.условие(код) }
    }
    private static func состояние(_ дескриптор: Int32) throws -> stat {
        var итог = stat()
        try требовать(fstat(дескриптор, &итог) == 0, "не-прочитаны-метаданные-коллекции")
        return итог
    }
    private static func идентичность(_ с: stat) -> String { "\(с.st_dev):\(с.st_ino)" }
    private static func токен(_ с: stat) -> String {
        "\(с.st_dev):\(с.st_ino):\(с.st_mode):\(с.st_uid):\(с.st_gid):\(с.st_nlink):\(с.st_size):\(с.st_flags):\(с.st_mtimespec.tv_sec):\(с.st_mtimespec.tv_nsec):\(с.st_ctimespec.tv_sec):\(с.st_ctimespec.tv_nsec)"
    }
    static func проверитьПредставлениеПустыхПрав(_ данные: Data) throws {
        try требовать(данные.count == 76 && MemoryLayout<attribute_set_t>.size == 20 && MemoryLayout<attrreference_t>.size == 8,
            "неизвестное-представление-расширенных-прав")
        func число(_ смещение: Int) -> UInt32 { данные.withUnsafeBytes { $0.loadUnaligned(fromByteOffset: смещение, as: UInt32.self) } }
        let ожидаемые = UInt32(ATTR_CMN_RETURNED_ATTRS) | UInt32(ATTR_CMN_EXTENDED_SECURITY)
        // Нативный ABI Darwin: длина 4, маски 20, attrreference 8, filesec без ACE 44.
        // Пропущенный returned bit, NOACL sentinel и неизвестные layout не доказывают пустоту.
        try требовать(число(0) == 76 && число(4) == ожидаемые && [8, 12, 16, 20].allSatisfy { число($0) == 0 }
            && число(24) == 8 && число(28) == 44 && число(32) == 0x012cc16d && число(68) == 0 && число(72) == 0,
            "не-подтверждено-пустое-представление-расширенных-прав")
    }
    private static func проверитьОтсутствиеРасширенныхПрав(_ дескриптор: Int32) throws {
        let до = try состояние(дескриптор)
        var запрос = attrlist()
        запрос.bitmapcount = UInt16(ATTR_BIT_MAP_COUNT)
        запрос.commonattr = UInt32(ATTR_CMN_RETURNED_ATTRS) | UInt32(ATTR_CMN_EXTENDED_SECURITY)
        var буфер = [UInt8](repeating: 0, count: 4096)
        let исход = буфер.withUnsafeMutableBytes {
            fgetattrlist(дескриптор, &запрос, $0.baseAddress!, $0.count, UInt32(FSOPT_REPORT_FULLSIZE))
        }
        try требовать(исход == 0, "не-прочитаны-расширенные-права-коллекции")
        let размер = буфер.withUnsafeBytes { $0.loadUnaligned(as: UInt32.self) }
        try требовать(размер == 76, "нет-положительного-свидетельства-пустых-прав")
        try проверитьПредставлениеПустыхПрав(Data(буфер.prefix(76)))
        try требовать((try токен(состояние(дескриптор))) == токен(до), "дрейф-при-чтении-расширенных-прав")
    }
    private static func открытьАбсолютный(_ путь: String) throws -> Int32 {
        try требовать(путь.utf8.count <= 4096 && путь.utf8.first == 47 && !путь.utf8.contains(0), "неверный-абсолютный-путь-коллекции")
        let части = ИменаПутей.компоненты(путь, сохранятьПустые: true).dropFirst()
        try требовать(!части.isEmpty && части.count <= 128 && части.allSatisfy { !$0.isEmpty && $0 != "." && $0 != ".." && $0.utf8.count <= 255 }, "неверные-компоненты-корня-коллекции")
        var текущий = open("/", O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC), оставить = false
        try требовать(текущий >= 0, "не-открыт-абсолютный-корень")
        defer { if !оставить { close(текущий) } }
        for часть in части {
            var до = stat()
            try требовать(fstatat(текущий, часть, &до, AT_SYMLINK_NOFOLLOW) == 0 && до.st_mode & S_IFMT == S_IFDIR, "не-каталог-в-абсолютном-пути")
            let следующий = openat(текущий, часть, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            try требовать(следующий >= 0, "не-открыт-компонент-корня")
            do {
                let после = try состояние(следующий)
                try требовать(токен(после) == токен(до), "дрейф-компонента-корня")
            } catch { close(следующий); throw error }
            close(текущий); текущий = следующий
        }
        оставить = true
        return текущий
    }
    private static func имеетПредка(_ предок: stat, _ дескриптор: Int32) throws -> Bool {
        var текущий = fcntl(дескриптор, F_DUPFD_CLOEXEC, 0)
        try требовать(текущий >= 0, "не-дублирован-корень-ограды")
        defer { close(текущий) }
        for _ in 0..<256 {
            let с = try состояние(текущий)
            if идентичность(с) == идентичность(предок) { return true }
            let следующий = openat(текущий, "..", O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            try требовать(следующий >= 0, "не-открыт-предок-коллекции")
            let следующийСтат: stat
            do { следующийСтат = try состояние(следующий) } catch { close(следующий); throw error }
            if идентичность(следующийСтат) == идентичность(с) { close(следующий); return false }
            close(текущий); текущий = следующий
        }
        throw ОтказСсылокПакета.условие("предел-предков-коллекции")
    }
    static func проверить(каталог: URL, внеРабочегоДерева: URL, учёт: УчтённаяКоллекцияКандидатов,
        послеЧтенияДляПроверки: (() throws -> Void)? = nil,
        послеСтатДляПроверки: ((String) throws -> Void)? = nil) throws -> ПровереннаяКоллекцияНаДиске {
        var ожидаемыеКаталоги: Set<String> = [""], соседи: [String: Set<String>] = ["": []]
        let файлы = Dictionary(uniqueKeysWithValues: учёт.артефакты.map { ($0.путь, $0) })
        var работаПутей = 0
        for запись in учёт.артефакты {
            let части = ИменаПутей.компоненты(запись.путь)
            var родитель = ""
            for (номер, часть) in части.enumerated() {
                try требовать(родитель.utf8.count + часть.utf8.count + 1 <= 67_108_864 - работаПутей, "предел-путей-физической-коллекции")
                работаПутей += родитель.utf8.count + часть.utf8.count + 1
                соседи[родитель, default: []].insert(часть)
                if номер + 1 < части.count {
                    родитель = родитель.isEmpty ? часть : родитель + "/" + часть
                    ожидаемыеКаталоги.insert(родитель)
                    try требовать(ожидаемыеКаталоги.count <= 32_768 && ожидаемыеКаталоги.count + файлы.count <= 65_536, "предел-каталогов-физической-коллекции")
                    if соседи[родитель] == nil { соседи[родитель] = [] }
                }
            }
        }
        let корневой = try открытьАбсолютный(каталог.path)
        defer { close(корневой) }
        let ограда = try открытьАбсолютный(внеРабочегоДерева.path)
        defer { close(ограда) }
        let корневые = try состояние(корневой), ограждённые = try состояние(ограда)
        try требовать(корневые.st_uid == geteuid() && корневые.st_mode & 0o7777 == 0o700, "не-частный-корень-коллекции")
        try требовать(!(try имеетПредка(ограждённые, корневой)) && !(try имеетПредка(корневые, ограда)), "коллекция-пересекает-рабочее-дерево")
        var состояния: [String: String] = [:], найденныеФайлы: Set<String> = [], иноды: Set<String> = []
        var просмотрено = 0, байтыИмён = 0, прочитано = 0, хэш = SHA256()
        func поле(_ строка: String) {
            var длина = UInt64(строка.utf8.count).bigEndian
            withUnsafeBytes(of: &длина) { хэш.update(data: Data($0)) }
            хэш.update(data: Data(строка.utf8))
        }
        поле("fum.физическая-коллекция-кандидатов.1"); поле(учёт.хэшСостава); поле(идентичность(корневые))
        func имена(_ дескриптор: Int32, _ родитель: String) throws -> [String] {
            let копия = fcntl(дескриптор, F_DUPFD_CLOEXEC, 0)
            guard копия >= 0, let поток = fdopendir(копия) else {
                if копия >= 0 { close(копия) }
                throw ОтказСсылокПакета.условие("не-открыт-поток-каталога-коллекции")
            }
            defer { closedir(поток) }
            rewinddir(поток)
            var имена: Set<String> = []
            errno = 0
            while let запись = readdir(поток) {
                var имя = запись.pointee.d_name
                let байты = withUnsafeBytes(of: &имя) { Data($0.prefix(while: { $0 != 0 })) }
                if байты == Data([46]) || байты == Data([46, 46]) { errno = 0; continue }
                try требовать(просмотрено < 131_072 && байты.count <= 67_108_864 - байтыИмён && !байты.isEmpty
                    && байты.count <= 255 && байты.allSatisfy { (97...122).contains($0) || (48...57).contains($0) || [45, 46].contains($0) }, "предел-или-имя-физической-коллекции")
                просмотрено += 1; байтыИмён += байты.count
                let текст = String(decoding: байты, as: UTF8.self)
                try требовать(соседи[родитель]?.contains(текст) == true && имена.insert(текст).inserted, "неучтённое-имя-физической-коллекции")
                errno = 0
            }
            try требовать(errno == 0 && имена == соседи[родитель], "неполное-перечисление-физической-коллекции")
            return имена.sorted()
        }
        func прочитать(_ дескриптор: Int32, _ запись: АртефактКандидатов) throws {
            var буфер = [UInt8](repeating: 0, count: 65_536), локально = 0, хэшФайла = SHA256()
            while true {
                let запрос = min(буфер.count, запись.размер - локально + 1)
                let число = буфер.withUnsafeMutableBytes { Darwin.read(дескриптор, $0.baseAddress!, запрос) }
                if число < 0 && errno == EINTR { continue }
                try требовать(число >= 0, "ошибка-чтения-физической-коллекции")
                if число == 0 { break }
                try требовать(число <= запись.размер - локально && число <= учёт.предел - прочитано, "предел-байтов-физической-коллекции")
                локально += число; прочитано += число
                хэшФайла.update(data: Data(буфер.prefix(число)))
            }
            let полученный = хэшФайла.finalize().map { String(format: "%02x", $0) }.joined()
            try требовать(локально == запись.размер && полученный == запись.хэш, "дрейф-байтов-физической-коллекции")
            поле(полученный)
        }
        func проверитьВид(_ с: stat, каталог: Bool) throws {
            try требовать(с.st_dev == корневые.st_dev && с.st_uid == geteuid()
                && с.st_mode & S_IFMT == (каталог ? S_IFDIR : S_IFREG)
                && с.st_mode & 0o7777 == (каталог ? 0o700 : 0o600)
                && (каталог || с.st_nlink == 1), "неверный-вид-режим-или-связность-физической-коллекции")
        }
        func обойти(_ дескриптор: Int32, _ родитель: String, поздний: Bool) throws {
            let до = try состояние(дескриптор)
            try проверитьВид(до, каталог: true)
            try проверитьОтсутствиеРасширенныхПрав(дескриптор)
            if поздний { try требовать(состояния[родитель] == токен(до), "поздний-дрейф-каталога-коллекции") }
            else { состояния[родитель] = токен(до); try требовать(иноды.insert(идентичность(до)).inserted, "повтор-физического-inode"); поле(родитель); поле(токен(до)) }
            for имя in try имена(дескриптор, родитель) {
                let путь = родитель.isEmpty ? имя : родитель + "/" + имя, этоКаталог = ожидаемыеКаталоги.contains(путь)
                var поИмени = stat()
                try требовать(fstatat(дескриптор, имя, &поИмени, AT_SYMLINK_NOFOLLOW) == 0, "нет-точного-имени-физической-коллекции")
                try проверитьВид(поИмени, каталог: этоКаталог)
                if !поздний { try послеСтатДляПроверки?(путь) }
                let файл = openat(дескриптор, имя, O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC | (этоКаталог ? O_DIRECTORY : 0))
                try требовать(файл >= 0, "не-открыт-объект-физической-коллекции")
                defer { close(файл) }
                let открытый = try состояние(файл)
                try проверитьВид(открытый, каталог: этоКаталог)
                try проверитьОтсутствиеРасширенныхПрав(файл)
                try требовать(токен(открытый) == токен(поИмени), "подмена-физического-inode")
                if этоКаталог { try обойти(файл, путь, поздний: поздний) }
                else if поздний { try требовать(состояния[путь] == токен(открытый), "поздний-дрейф-файла-коллекции") }
                else {
                    guard let запись = файлы[путь] else { throw ОтказСсылокПакета.условие("нет-записи-физического-файла") }
                    try требовать(открытый.st_size == Int64(запись.размер) && иноды.insert(идентичность(открытый)).inserted
                        && найденныеФайлы.insert(путь).inserted, "неверный-размер-или-повтор-физического-файла")
                    состояния[путь] = токен(открытый); поле(путь); поле(токен(открытый))
                    try прочитать(файл, запись)
                }
                var после = stat()
                try требовать(fstatat(дескриптор, имя, &после, AT_SYMLINK_NOFOLLOW) == 0
                    && токен(после) == токен(открытый) && (try токен(состояние(файл))) == токен(открытый), "дрейф-привязки-физического-файла")
            }
            try требовать((try токен(состояние(дескриптор))) == токен(до), "дрейф-каталога-при-обходе")
        }
        try обойти(корневой, "", поздний: false)
        try послеЧтенияДляПроверки?()
        try обойти(корневой, "", поздний: true)
        let повторный = try открытьАбсолютный(каталог.path)
        defer { close(повторный) }
        let повторнаяОграда = try открытьАбсолютный(внеРабочегоДерева.path)
        defer { close(повторнаяОграда) }
        let итоговыйКорень = try состояние(повторный), итоговаяОграда = try состояние(повторнаяОграда)
        try требовать(токен(итоговаяОграда) == токен(ограждённые)
            && !(try имеетПредка(итоговаяОграда, повторный)) && !(try имеетПредка(итоговыйКорень, повторнаяОграда)), "поздний-дрейф-ограды-коллекции")
        try проверитьОтсутствиеРасширенныхПрав(повторный)
        try требовать(токен(итоговыйКорень) == токен(корневые) && найденныеФайлы.count == файлы.count
            && прочитано == учёт.занято, "неполный-или-перемещённый-корень-коллекции")
        return .init(идентичностьКорня: идентичность(корневые), хэшУчёта: учёт.хэшСостава,
            хэшНаблюдений: хэш.finalize().map { String(format: "%02x", $0) }.joined(), файлы: файлы.count,
            каталоги: ожидаемыеКаталоги.count, прочитаноБайтов: прочитано)
    }
}

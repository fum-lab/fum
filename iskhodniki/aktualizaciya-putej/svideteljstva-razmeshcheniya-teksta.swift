import Foundation

enum РольДиапазонаТекста: String, Codable, Sendable { case служебный, дословный, неизвестный }
struct ДиапазонРолиТекста: Codable, Equatable, Sendable {
    var начало: Int
    var длина: Int
    var роль: РольДиапазонаТекста
}
struct КопияДословногоТекста: Codable, Equatable, Sendable {
    var источник: String
    var хэшИсточника: String
    var началоИсточника: Int
    var началоДокумента: Int
    var длина: Int
    var хэшКопии: String
}
struct ПланРазмещенияТекста: Codable, Sendable {
    var схема = "fum.размещение-дословных-байтов.1"
    var путь: String
    var хэшДокумента: String
    var размерДокумента: Int
    var хэшКорпуса: String
    var хэшПолитики: String
    var диапазоны: [ДиапазонРолиТекста]
    var копии: [КопияДословногоТекста]
}
struct ИсточникДословныхБайтов: Sendable {
    var имя: String
    var байты: Data
    var ожидаемыйХэш: String
    var происхождение: String
}
struct ПроверенноеРазмещениеТекста: Sendable {
    let путь: String
    let хэшДокумента: String
    let хэшПлана: String
    let хэшИсточников: String
    let хэшКорпуса: String
    let хэшПолитики: String
    let диапазоны: [ДиапазонРолиТекста]
    let копии: [КопияДословногоТекста]
    let размещениеБайтовПроверено = true
    let допускРолейПроверен = false
    let применениеРазрешено = false
    fileprivate init(путь: String, хэшДокумента: String, хэшПлана: String, хэшИсточников: String,
        хэшКорпуса: String, хэшПолитики: String, диапазоны: [ДиапазонРолиТекста], копии: [КопияДословногоТекста]) {
        self.путь = путь; self.хэшДокумента = хэшДокумента; self.хэшПлана = хэшПлана; self.хэшИсточников = хэшИсточников
        self.хэшКорпуса = хэшКорпуса; self.хэшПолитики = хэшПолитики
        self.диапазоны = диапазоны; self.копии = копии
    }
}
enum ПроверкаРазмещенияТекста {
    static func проверить(путь: String, документ: Data, план: Data, ожидаемыйХэшПлана: String,
        хэшКорпуса: String, политика: Data, ожидаемыйХэшПолитики: String, источники: [ИсточникДословныхБайтов]) throws -> ПроверенноеРазмещениеТекста {
        try ИменаПутей.проверитьПуть(путь)
        guard документ.count <= 33_554_432, String(data: документ, encoding: .utf8) != nil, план.count <= 4_194_304,
              верныйХэш(ожидаемыйХэшПлана), хэшПутей(план) == ожидаемыйХэшПлана, верныйХэш(хэшКорпуса),
              !политика.isEmpty, политика.count <= 4_194_304, верныйХэш(ожидаемыйХэшПолитики), хэшПутей(политика) == ожидаемыйХэшПолитики,
              источники.count <= 4096 else { throw ОтказКорпусаСсылок.условие("неверные-опоры-размещения") }
        let разбор = try ТокеныJSONМиграции.разобрать(план)
        let модель = try JSONDecoder().decode(ПланРазмещенияТекста.self, from: Data(план))
        guard разбор.ключиОбъектов[Data()] == ключи(["схема", "путь", "хэшДокумента", "размерДокумента", "хэшКорпуса", "хэшПолитики", "диапазоны", "копии"]),
              модель.схема == "fum.размещение-дословных-байтов.1", Data(модель.путь.utf8) == Data(путь.utf8),
              модель.размерДокумента == документ.count, модель.хэшДокумента == хэшПутей(документ),
              модель.хэшКорпуса == хэшКорпуса, модель.хэшПолитики == ожидаемыйХэшПолитики,
              модель.диапазоны.count <= 4096, модель.копии.count <= 8192 else { throw ОтказКорпусаСсылок.условие("дрейф-или-неверная-схема-размещения") }
        let байты = Data(документ), скаляры = Array(байты)
        func границаUTF8(_ позиция: Int) -> Bool { позиция == скаляры.count || скаляры[позиция] & 0xC0 != 0x80 }
        var конец = 0
        for (номер, часть) in модель.диапазоны.enumerated() {
            guard разбор.ключиОбъектов[Data("/диапазоны/\(номер)".utf8)] == ключи(["начало", "длина", "роль"]), часть.начало == конец else { throw ОтказКорпусаСсылок.условие("неполное-покрытие-ролями") }
            let область = try диапазон(часть.начало, часть.длина, всего: байты.count)
            guard границаUTF8(область.lowerBound), границаUTF8(область.upperBound) else { throw ОтказКорпусаСсылок.условие("роль-разрывает-UTF8") }
            конец = область.upperBound
        }
        guard конец == байты.count else { throw ОтказКорпусаСсылок.условие("не-замкнуто-покрытие-ролями") }
        var источникиПоИмени: [Data: ИсточникДословныхБайтов] = [:], сумма = 0
        for источник in источники {
            guard !источник.имя.isEmpty, источник.имя.utf8.count <= 256, !источник.имя.utf8.contains(0),
                  !источник.происхождение.isEmpty, источник.происхождение.utf8.count <= 1024,
                  источник.байты.count <= 33_554_432, источник.байты.count <= 134_217_728 - сумма,
                  верныйХэш(источник.ожидаемыйХэш), хэшПутей(источник.байты) == источник.ожидаемыйХэш,
                  источникиПоИмени[Data(источник.имя.utf8)] == nil else { throw ОтказКорпусаСсылок.условие("не-замкнут-исходный-буфер-размещения") }
            var нормализованный = источник; нормализованный.байты = Data(источник.байты)
            источникиПоИмени[Data(источник.имя.utf8)] = нормализованный
            сумма += источник.байты.count
        }
        var номерКопии = 0
        for часть in модель.диапазоны where часть.роль == .дословный {
            let область = try диапазон(часть.начало, часть.длина, всего: байты.count)
            var курсор = область.lowerBound
            while номерКопии < модель.копии.count, модель.копии[номерКопии].началоДокумента < область.upperBound {
                let копия = модель.копии[номерКопии]
                guard разбор.ключиОбъектов[Data("/копии/\(номерКопии)".utf8)] == ключи(["источник", "хэшИсточника", "началоИсточника", "началоДокумента", "длина", "хэшКопии"]),
                      копия.началоДокумента == курсор, let источник = источникиПоИмени[Data(копия.источник.utf8)], копия.хэшИсточника == источник.ожидаемыйХэш else { throw ОтказКорпусаСсылок.условие("нет-опоры-дословной-копии") }
                let исходный = try диапазон(копия.началоИсточника, копия.длина, всего: источник.байты.count)
                let целевой = try диапазон(копия.началоДокумента, копия.длина, всего: байты.count)
                guard целевой.upperBound <= область.upperBound, границаUTF8(целевой.lowerBound), границаUTF8(целевой.upperBound) else { throw ОтказКорпусаСсылок.условие("копия-пересекает-роль-или-UTF8") }
                let буквальные = байты.subdata(in: целевой)
                guard буквальные == источник.байты.subdata(in: исходный), верныйХэш(копия.хэшКопии), хэшПутей(буквальные) == копия.хэшКопии else { throw ОтказКорпусаСсылок.условие("не-совпали-дословные-байты") }
                курсор = целевой.upperBound; номерКопии += 1
            }
            guard курсор == область.upperBound else { throw ОтказКорпусаСсылок.условие("нет-полного-свидетельства-дословной-роли") }
        }
        guard номерКопии == модель.копии.count else { throw ОтказКорпусаСсылок.условие("лишняя-или-неупорядоченная-копия") }
        let опоры = источникиПоИмени.keys.sorted { $0.lexicographicallyPrecedes($1) }.map { ключ -> ОпораБайтРазмещения in
            let источник = источникиПоИмени[ключ]!
            return .init(имя: источник.имя, хэш: источник.ожидаемыйХэш, размер: источник.байты.count, происхождение: источник.происхождение)
        }
        return try .init(путь: путь, хэшДокумента: модель.хэшДокумента, хэшПлана: ожидаемыйХэшПлана, хэшИсточников: хэшПутей(байтыПлана(опоры)),
            хэшКорпуса: хэшКорпуса, хэшПолитики: ожидаемыйХэшПолитики, диапазоны: модель.диапазоны, копии: модель.копии)
    }

    private static func диапазон(_ начало: Int, _ длина: Int, всего: Int) throws -> Range<Int> {
        guard начало >= 0, начало <= всего, длина > 0, длина <= всего - начало else { throw ОтказКорпусаСсылок.условие("диапазон-вне-буфера") }
        return начало..<(начало + длина)
    }
    private static func верныйХэш(_ значение: String) -> Bool {
        значение.utf8.count == 64 && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
    private static func ключи(_ значения: [String]) -> Set<Data> { Set(значения.map { Data($0.utf8) }) }
}

private struct ОпораБайтРазмещения: Encodable {
    var имя: String
    var хэш: String
    var размер: Int
    var происхождение: String
}

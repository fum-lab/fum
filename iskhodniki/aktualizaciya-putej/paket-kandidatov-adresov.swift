import Foundation

indirect enum ЗначениеПакета: Sendable {
    case строка(String), число(Int), флаг(Bool), массив([ЗначениеПакета]), объект([(String, ЗначениеПакета)])
}
enum ФорматированныйПисательПакета {
    static func записать(_ значение: ЗначениеПакета, предел: Int) throws -> Data {
        guard (0...33_554_432).contains(предел) else { throw ОтказСсылокПакета.условие("неверный-предел-пакета") }
        func проход(_ сохранять: Bool, ёмкость: Int) throws -> (Int, Data) {
            var размер = 0, узлы = 0, байты = Data()
            if сохранять { байты.reserveCapacity(ёмкость) }
            func символ(_ знак: UInt8) throws {
                guard размер < предел else { throw ОтказСсылокПакета.условие("предел-выхода-пакета") }
                размер += 1
                if сохранять { байты.append(знак) }
            }
            func текст(_ строка: String) throws { for знак in строка.utf8 { try символ(знак) } }
            func отступ(_ глубина: Int) throws { for _ in 0..<(глубина * 2) { try символ(32) } }
            func строка(_ значение: String) throws {
                try символ(34)
                for знак in значение.utf8 {
                    switch знак {
                    case 34: try текст("\\\"")
                    case 92: try текст("\\\\")
                    case 8: try текст("\\b")
                    case 9: try текст("\\t")
                    case 10: try текст("\\n")
                    case 12: try текст("\\f")
                    case 13: try текст("\\r")
                    case 0...31: try текст(String(format: "\\u%04x", знак))
                    default: try символ(знак)
                    }
                }
                try символ(34)
            }
            func обойти(_ значение: ЗначениеПакета, _ глубина: Int) throws {
                guard глубина <= 32, узлы < 2_000_000 else { throw ОтказСсылокПакета.условие("предел-структуры-пакета") }
                узлы += 1
                switch значение {
                case .строка(let с): try строка(с)
                case .число(let ч): try текст(String(ч))
                case .флаг(let ф): try текст(ф ? "true" : "false")
                case .массив(let элементы):
                    try символ(91)
                    for (номер, элемент) in элементы.enumerated() {
                        try символ(10); try отступ(глубина + 1); try обойти(элемент, глубина + 1)
                        if номер + 1 < элементы.count { try символ(44) }
                    }
                    if !элементы.isEmpty { try символ(10); try отступ(глубина) }
                    try символ(93)
                case .объект(let поля):
                    try символ(123)
                    var ключи: Set<Data> = []
                    for (номер, поле) in поля.enumerated() {
                        guard поле.0.utf8.count <= 1024 else { throw ОтказСсылокПакета.условие("предел-ключа-пакета") }
                        guard ключи.insert(Data(поле.0.utf8)).inserted else { throw ОтказСсылокПакета.условие("дубли-ключей-пакета") }
                        try символ(10); try отступ(глубина + 1); try строка(поле.0); try текст(": "); try обойти(поле.1, глубина + 1)
                        if номер + 1 < поля.count { try символ(44) }
                    }
                    if !поля.isEmpty { try символ(10); try отступ(глубина) }
                    try символ(125)
                }
            }
            try обойти(значение, 0); try символ(10)
            return (размер, байты)
        }
        let размер = try проход(false, ёмкость: 0).0
        let результат = try проход(true, ёмкость: размер)
        guard результат.0 == размер, результат.1.count == размер else { throw ОтказСсылокПакета.условие("дрейф-размера-пакета") }
        return результат.1
    }
}

enum УпаковщикКандидатовАдресов {
    static func упаковать(_ документ: ДокументСсылокПакета, ожидаемая: ОжидаемаяЗаписьПорции,
        перечень: ПереченьАдресовДокумента, кандидаты: КандидатыРазрешенияДокумента,
        пределВыхода: Int = 33_554_432, пределХэшируемыхБайтов: Int = 67_108_864) throws -> Data {
        func требовать(_ условие: Bool, _ код: String) throws {
            if !условие { throw ОтказСсылокПакета.условие(код) }
        }
        func хэшВерный(_ значение: String) -> Bool {
            значение.utf8.count == 64 && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
        }
        let опора = ожидаемая.документ
        try требовать((0...33_554_432).contains(пределВыхода) && (0...67_108_864).contains(пределХэшируемыхБайтов), "неверные-пределы-пакета")
        try требовать(документ.путь.utf8.count <= 1024 && перечень.путь.utf8.count <= 1024 && кандидаты.путь.utf8.count <= 1024
            && хэшВерный(документ.sha256) && хэшВерный(перечень.заявленныйХэш)
            && хэшВерный(кандидаты.хэшДокумента) && хэшВерный(кандидаты.хэшКонтекста), "ранний-предел-метаданных-пакета")
        try требовать(документ.байты.count <= 33_554_432 && документ.байты.count == опора.размер
            && Data(документ.путь.utf8) == Data(опора.путь.utf8) && документ.sha256 == опора.хэш, "документ-вне-записи-плана")
        try требовать(хэшВерный(документ.sha256) && кандидаты.хэшКонтекста == ожидаемая.опоры.контекст
            && Data(перечень.путь.utf8) == Data(документ.путь.utf8) && Data(кандидаты.путь.utf8) == Data(документ.путь.utf8)
            && перечень.заявленныйХэш == документ.sha256 && кандидаты.хэшДокумента == документ.sha256 && перечень.размер == опора.размер, "разные-опоры-пакета")
        try требовать(перечень.узлы.count <= 16_384 && перечень.ошибки.count <= 16_384 && кандидаты.вхождения.count <= 16_384
            && кандидаты.упоминания.count <= 16_384 && кандидаты.неразобранныеУзлы.count <= 16_384 && кандидаты.ошибки.count <= 16_384, "предел-строк-пакета")
        let маски = [перечень.неизвестныеДиапазоны, перечень.скрытыеДиапазоны, перечень.эвристическиЗащищённыеДиапазоны, перечень.неподдержанныеКонтейнеры]
        try требовать(маски.allSatisfy { $0.count <= 16_384 }, "предел-масок-пакета")
        let байты = Data(документ.байты), верныйТекст = String(data: байты, encoding: .utf8) != nil
        try требовать(верныйТекст || (перечень.узлы.isEmpty && кандидаты.вхождения.isEmpty && кандидаты.упоминания.isEmpty
            && !перечень.обходЗавершён && !перечень.синтаксисПолностьюРаспознан && !кандидаты.всеЗаявленныеУзлыУчтены
            && !перечень.ошибки.isEmpty && !кандидаты.ошибки.isEmpty && перечень.неизвестныеДиапазоны == [0..<байты.count]
            && перечень.скрытыеДиапазоны.isEmpty && перечень.эвристическиЗащищённыеДиапазоны.isEmpty && перечень.неподдержанныеКонтейнеры.isEmpty),
            "ложная-форма-неизвестной-кодировки")
        var работа = 0
        func учесть(_ число: Int) throws {
            try требовать(число >= 0 && число <= пределХэшируемыхБайтов - работа, "предел-хэширования-пакета")
            работа += число
        }
        func диапазон(_ значение: Range<Int>) throws {
            try требовать(значение.lowerBound >= 0 && значение.upperBound <= байты.count && значение.lowerBound <= значение.upperBound, "диапазон-вне-пакета")
            if верныйТекст {
                for позиция in [значение.lowerBound, значение.upperBound] where позиция < байты.count {
                    try требовать(байты[позиция] & 0xC0 != 0x80, "разрыв-кодировки-пакета")
                }
            }
        }
        func строка(_ значение: String?, предел: Int) throws {
            if let значение { try требовать(значение.utf8.count <= предел, "предел-строки-пакета"); try учесть(значение.utf8.count) }
        }
        try учесть(байты.count); try учесть(документ.путь.utf8.count)
        let узлы = перечень.узлы
        var связи = 0
        for (номер, узел) in узлы.enumerated() {
            try требовать(узел.номер == номер && (номер == 0 || узлы[номер - 1].целиком.lowerBound <= узел.целиком.lowerBound), "порядок-узлов-пакета")
            try диапазон(узел.целиком)
            for часть in [узел.адрес, узел.подпись, узел.метка].compactMap({ $0 }) {
                try диапазон(часть)
                try требовать(часть.lowerBound >= узел.целиком.lowerBound && часть.upperBound <= узел.целиком.upperBound, "поддиапазон-вне-узла-пакета")
            }
            try требовать(узел.определения.count <= 16_384 - связи, "предел-связей-пакета"); связи += узел.определения.count
            var замечены: Set<Int> = []
            for номер in узел.определения {
                try требовать(узлы.indices.contains(номер) && узлы[номер].вид == .определение && замечены.insert(номер).inserted, "неверная-связь-пакета")
            }
            try строка(узел.ключМетки, предел: 33_554_432)
        }
        for ошибка in перечень.ошибки { try диапазон(ошибка.диапазон); try строка(ошибка.код, предел: 256) }
        for маска in маски { for часть in маска { try диапазон(часть) } }
        var назначены: Set<Int> = []
        for вхождение in кандидаты.вхождения {
            try требовать(узлы.indices.contains(вхождение.номерУзла) && назначены.insert(вхождение.номерУзла).inserted, "неверный-узел-вхождения-пакета")
            let узел = узлы[вхождение.номерУзла]
            try требовать((узел.вид == .определение || узел.вид == .встроенная) && узел.адрес == вхождение.адрес, "адрес-вхождения-вне-узла")
            try диапазон(вхождение.адрес); try диапазон(вхождение.суффикс)
            try требовать(вхождение.суффикс.lowerBound >= вхождение.адрес.lowerBound && вхождение.суффикс.upperBound == вхождение.адрес.upperBound, "суффикс-вне-адреса-пакета")
            try учесть(вхождение.адрес.count); try учесть(вхождение.суффикс.count)
            for хэш in [вхождение.хэшАдреса, вхождение.хэшСуффикса].compactMap({ $0 }) { try требовать(хэшВерный(хэш), "неверный-хэш-вхождения-пакета") }
            // Отказная старая цель ещё не обязана существовать в пространстве:
            // до поиска решатель добавляет к адресу базу документа.
            try строка(вхождение.прежняяЦель, предел: 16_384 + 1024)
            for путь in [вхождение.будущаяЦель, вхождение.граница] { try строка(путь, предел: 1024) }
            try строка(вхождение.новыйПутьАдреса, предел: 16_384); try строка(вхождение.ошибка, предел: 256)
        }
        связи = 0
        for упоминание in кандидаты.упоминания {
            try требовать(узлы.indices.contains(упоминание.номерУзла) && назначены.insert(упоминание.номерУзла).inserted, "неверный-узел-упоминания-пакета")
            let узел = узлы[упоминание.номерУзла]
            try требовать([ВидУзлаПеречняАдресов.полная, .свёрнутая, .сокращённая].contains(узел.вид) && упоминание.определения == узел.определения
                && упоминание.определения.count <= 16_384 - связи, "неверные-определения-упоминания-пакета")
            связи += упоминание.определения.count
            if let номер = упоминание.вхождение {
                try требовать(кандидаты.вхождения.indices.contains(номер) && упоминание.определения.count == 1
                    && упоминание.определения[0] == кандидаты.вхождения[номер].номерУзла, "неверный-индекс-вхождения-пакета")
            }
            try строка(упоминание.ошибка, предел: 256)
        }
        for номер in кандидаты.неразобранныеУзлы {
            try требовать(узлы.indices.contains(номер) && назначены.insert(номер).inserted, "неверный-неизвестный-узел-пакета")
        }
        try требовать(!кандидаты.всеЗаявленныеУзлыУчтены || назначены.count == узлы.count, "неполное-покрытие-узлов-пакета")
        for ошибка in кандидаты.ошибки { try строка(ошибка, предел: 256) }
        // Проверки суммарной работы закончены до повторного хэширования.
        try требовать(хэшПутей(байты) == документ.sha256, "дрейф-байтов-пакета")
        for вхождение in кандидаты.вхождения {
            if let хэш = вхождение.хэшАдреса { try требовать(хэшПутей(байты.subdata(in: вхождение.адрес)) == хэш, "дрейф-адреса-пакета") }
            if let хэш = вхождение.хэшСуффикса { try требовать(хэшПутей(байты.subdata(in: вхождение.суффикс)) == хэш, "дрейф-суффикса-пакета") }
        }
        func границы(_ часть: Range<Int>?) -> ЗначениеПакета { .массив(часть.map { [.число($0.lowerBound), .число($0.upperBound)] } ?? []) }
        func отпечаток(_ значение: String?) -> ЗначениеПакета {
            guard let значение else { return .массив([]) }
            return .массив([.строка(хэшПутей(Data(значение.utf8))), .число(значение.utf8.count)])
        }
        func необязательныйХэш(_ значение: String?) -> ЗначениеПакета { .массив(значение.map { [.строка($0)] } ?? []) }
        func числа(_ значения: [Int]) -> ЗначениеПакета { .массив(значения.map { .число($0) }) }
        let лексика: [ЗначениеПакета] = узлы.map { узел in
            let флаги = (узел.изображение ? 1 : 0) | (узел.эвристическиЗащищён ? 2 : 0) | (узел.неподдержанныйКонтейнер ? 4 : 0)
            return .массив([.число(узел.номер), .строка(узел.вид.rawValue), границы(узел.целиком), границы(узел.адрес),
                границы(узел.подпись), границы(узел.метка), числа(узел.определения), .число(флаги), отпечаток(узел.ключМетки)])
        }
        let вхождения: [ЗначениеПакета] = кандидаты.вхождения.enumerated().map { номер, вхождение in
            .массив([.число(номер), .число(вхождение.номерУзла), границы(вхождение.адрес), границы(вхождение.суффикс), .строка(вхождение.вид.rawValue),
                необязательныйХэш(вхождение.хэшАдреса), необязательныйХэш(вхождение.хэшСуффикса), отпечаток(вхождение.прежняяЦель),
                .массив(вхождение.видПрежнейЦели.map { [.строка($0.rawValue)] } ?? []), отпечаток(вхождение.будущаяЦель), отпечаток(вхождение.граница),
                отпечаток(вхождение.новыйПутьАдреса), .флаг(вхождение.сохранёнИсходныйПуть), отпечаток(вхождение.ошибка)])
        }
        let упоминания: [ЗначениеПакета] = кандидаты.упоминания.map { упоминание in
            .массив([.число(упоминание.номерУзла), числа(упоминание.определения), .массив(упоминание.вхождение.map { [.число($0)] } ?? []), отпечаток(упоминание.ошибка)])
        }
        let значение = ЗначениеПакета.объект([
            ("схема", .строка("fum.пакет-диагностики-кандидатов.1")), ("номерДокумента", .число(ожидаемая.номер)),
            ("путь", отпечаток(документ.путь)), ("хэшДокумента", .строка(документ.sha256)), ("размерДокумента", .число(байты.count)),
            ("хэшПлана", .строка(ожидаемая.хэшПлана)), ("хэшКонтекста", .строка(кандидаты.хэшКонтекста)),
            ("хэшОжидания", .строка(ожидаемая.опоры.ожидание)), ("хэшФизическогоСнимка", .строка(ожидаемая.опоры.физическийСнимок)),
            ("хэшСобственногоИсточника", .строка(ожидаемая.опоры.собственныйИсточник)), ("переданныеБайтыСвязаны", .флаг(true)),
            ("исходнаяКодировкаВерна", .флаг(верныйТекст)), ("хэшПеречняПроверен", .флаг(перечень.хэшПроверен)),
            ("обходЗавершён", .флаг(перечень.обходЗавершён)), ("синтаксисПолностьюРаспознан", .флаг(перечень.синтаксисПолностьюРаспознан)),
            ("узлы", .массив(лексика)), ("вхождения", .массив(вхождения)), ("упоминания", .массив(упоминания)),
            ("неразобранныеУзлы", числа(кандидаты.неразобранныеУзлы)),
            ("ошибкиРазметки", .массив(перечень.ошибки.map { .массив([отпечаток($0.код), границы($0.диапазон)]) })),
            ("маски", .массив(маски.map { .массив($0.map { границы($0) }) })),
            ("ошибкиРазрешения", .массив(кандидаты.ошибки.map { отпечаток($0) })),
            ("всеЗаявленныеУзлыУчтены", .флаг(кандидаты.всеЗаявленныеУзлыУчтены)),
            ("происхождениеПеречняПроверено", .флаг(false)), ("ролиПроверены", .флаг(false)), ("целиПроверены", .флаг(false)),
            ("якоряИЗапросыПроверены", .флаг(false)), ("применениеРазрешено", .флаг(false))])
        return try ФорматированныйПисательПакета.записать(значение, предел: пределВыхода)
    }
}

import Foundation

struct НамерениеОкнаДиагностики: Sendable {
    let окно: String
    let опоры: ОпорыОкнаДиагностики
    let хэшПлана: String
    let хэшПредыдущейТочки: String?
    let перваяПорция: Int
    let числоПорций: Int
}
struct СвязанноеУправлениеОкна: Sendable {
    let намерение: НамерениеОкнаДиагностики
    let попытка: ПопыткаОкнаДиагностики
    let артефактМанифеста: АртефактКандидатов
    let каноническиеУправляющиеБайтыПроверены = true
    let физическиеФайлыПроверены = false
    let терминальныйПроцессПроверен = false
    let запускРазрешён = false
    fileprivate init(намерение: НамерениеОкнаДиагностики, попытка: ПопыткаОкнаДиагностики, артефактМанифеста: АртефактКандидатов) {
        self.намерение = намерение; self.попытка = попытка; self.артефактМанифеста = артефактМанифеста
    }
}
enum УправлениеПопыткиОкна: Sendable {
    case связанное(СвязанноеУправлениеОкна), несвязанное(ПопыткаОкнаДиагностики)
}
struct ОкноСоСвязаннымУправлением: Sendable {
    let окно: ПроверенноеСтруктурноеОкно
    let каноническиеУправляющиеБайтыПроверены = true
    let физическиеФайлыПроверены = false
    let терминальныйПроцессПроверен = false
    let текущаяГоловаПроверена = false
    let внешняяИсторияПроверена = false
    let запускРазрешён = false
    let продолжениеРазрешено = false
    let применениеРазрешено = false
    fileprivate init(_ окно: ПроверенноеСтруктурноеОкно) { self.окно = окно }
}
enum СвязываниеУправленияОкна {
    private static func требовать(_ условие: Bool, _ код: String) throws {
        if !условие { throw ОтказСсылокПакета.условие(код) }
    }
    private static func верныйХэш(_ значение: String) -> Bool {
        значение.utf8.count == 64 && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
    private static func проверитьНомер(_ номер: String) throws {
        try требовать(номер.utf8.count == 36 && UUID(uuidString: номер)?.uuidString.lowercased() == номер, "неверный-номер-управления-окна")
    }
    private static func поля(_ окно: String, _ о: ОпорыОкнаДиагностики) throws -> [(String, ЗначениеПакета)] {
        try проверитьНомер(окно); try проверитьНомер(о.коллекция)
        try требовать([о.хэшПрофиля, о.хэшИсточникаПроизводителя, о.хэшСредыПроизводителя].allSatisfy(верныйХэш), "неверные-опоры-управления-окна")
        return [("окно", .строка(окно)), ("коллекция", .строка(о.коллекция)), ("хэшПрофиля", .строка(о.хэшПрофиля)),
            ("хэшИсточникаПроизводителя", .строка(о.хэшИсточникаПроизводителя)), ("хэшСредыПроизводителя", .строка(о.хэшСредыПроизводителя))]
    }
    static func байтыНамерения(_ н: НамерениеОкнаДиагностики) throws -> Data {
        let общие = try поля(н.окно, н.опоры)
        try требовать(верныйХэш(н.хэшПлана) && (н.хэшПредыдущейТочки.map(верныйХэш) ?? true)
            && (0..<8192).contains(н.перваяПорция) && (1...4).contains(н.числоПорций), "неверная-граница-намерения-окна")
        return try ФорматированныйПисательПакета.записать(.объект([("схема", .строка("fum.намерение-окна-кандидатов.1"))] + общие + [
            ("хэшПлана", .строка(н.хэшПлана)), ("хэшПредыдущейТочки", .массив(н.хэшПредыдущейТочки.map { [.строка($0)] } ?? [])),
            ("перваяПорция", .число(н.перваяПорция)), ("числоПорций", .число(н.числоПорций))]), предел: 16_384)
    }
    static func байтыТерминала(_ т: ТерминалОкнаДиагностики) throws -> Data {
        let общие = try поля(т.окно, т.опоры)
        try требовать((0...255).contains(т.кодВыхода) && верныйХэш(т.хэшМанифеста) && верныйХэш(т.хэшНамерения), "неверные-поля-терминала-окна")
        // Ссылка на сам файл терминала не входит в его байты.
        return try ФорматированныйПисательПакета.записать(.объект([("схема", .строка("fum.терминал-окна-кандидатов.1"))] + общие + [
            ("кодОбычногоВыхода", .число(т.кодВыхода)), ("хэшНамерения", .строка(т.хэшНамерения)),
            ("хэшМанифеста", .строка(т.хэшМанифеста))]), предел: 16_384)
    }
    static func связать(намерение: НамерениеОкнаДиагностики, байтыНамерения: Data, артефактНамерения: АртефактКандидатов,
        терминал: ТерминалОкнаДиагностики, байтыТерминала: Data, манифест: МанифестОкнаДиагностики,
        байтыМанифеста: Data, артефактМанифеста: АртефактКандидатов, учёт: УчтённаяКоллекцияКандидатов) throws -> СвязанноеУправлениеОкна {
        try требовать(байтыНамерения.count <= 16_384 && байтыТерминала.count <= 16_384 && байтыМанифеста.count <= 1_048_576
            && !учёт.содержитНеизвестныеОстатки, "ранний-предел-байтов-управления-окна")
        let каноническоеНамерение = try Self.байтыНамерения(намерение), каноническийТерминал = try Self.байтыТерминала(терминал)
        let каноническийМанифест = try ПроверкаОкнаКандидатов.байтыМанифеста(манифест)
        try требовать(намерение.окно == терминал.окно && намерение.окно == манифест.окно
            && намерение.опоры == терминал.опоры && намерение.опоры == манифест.опоры
            && учёт.идентификатор == намерение.опоры.коллекция && учёт.хэшПрофиля == намерение.опоры.хэшПрофиля
            && намерение.хэшПлана == манифест.хэшПлана && намерение.перваяПорция == манифест.перваяПорция
            && намерение.числоПорций == манифест.числоПорций && намерение.хэшПредыдущейТочки == манифест.хэшПредыдущейТочки
            && манифест.хэшНамерения == артефактНамерения.хэш && терминал.хэшНамерения == артефактНамерения.хэш
            && терминал.хэшМанифеста == артефактМанифеста.хэш, "несогласованные-поля-управления-окна")
        let пары = [(артефактНамерения, байтыНамерения, каноническоеНамерение),
            (терминал.артефакт, байтыТерминала, каноническийТерминал), (артефактМанифеста, байтыМанифеста, каноническийМанифест)]
        var пути: Set<Data> = []
        for (а, сырые, канонические) in пары {
            try ИменаПутей.проверитьПуть(а.путь)
            try требовать(а.путь.utf8.allSatisfy { (97...122).contains($0) || (48...57).contains($0) || [45, 46, 47].contains($0) }
                && верныйХэш(а.хэш) && (0...1_048_576).contains(а.размер) && а.роль == .управление, "неверная-ссылка-управления-окна")
            try требовать(пути.insert(Data(а.путь.utf8)).inserted && учёт.артефакты.contains(а), "неучтённая-или-повторная-ссылка-управления")
            try требовать(сырые == канонические && а.размер == сырые.count && а.хэш == хэшПутей(сырые), "дрейф-канонических-байтов-управления")
        }
        return .init(намерение: намерение, попытка: .init(окно: намерение.окно, намерение: артефактНамерения,
            терминал: .обычныйВыход(терминал)), артефактМанифеста: артефактМанифеста)
    }
    static func проверитьОкно(план: ПланПорцийКандидатов, опоры: ОпорыОкнаДиагностики, предыдущая: ПредыдущаяГраницаДиагностики,
        управление: [УправлениеПопыткиОкна], учёт: УчтённаяКоллекцияКандидатов, манифест: МанифестОкнаДиагностики,
        байтыМанифеста: Data, артефактМанифеста: АртефактКандидатов) throws -> ОкноСоСвязаннымУправлением {
        try требовать(!управление.isEmpty && управление.count <= 8192, "ранний-предел-истории-управления")
        var история: [ПопыткаОкнаДиагностики] = []
        for запись in управление {
            guard case .связанное(let связь) = запись else { throw ОтказСсылокПакета.условие("несвязанная-попытка-блокирует-историю") }
            история.append(связь.попытка)
        }
        guard case .связанное(let текущая) = управление[управление.count - 1] else { throw ОтказСсылокПакета.условие("нет-текущего-управления") }
        try требовать(текущая.артефактМанифеста == артефактМанифеста, "подмена-манифеста-связанного-окна")
        let окно = try ПроверкаОкнаКандидатов.проверить(план: план, опоры: опоры, предыдущая: предыдущая, история: история,
            учёт: учёт, манифест: манифест, байтыМанифеста: байтыМанифеста, артефактМанифеста: артефактМанифеста)
        return .init(окно)
    }
}

import Foundation

struct ДоказательствоКопииДокументации: Codable, Equatable, Sendable {
    var исходный: String
    var целевой: String
    var исходныйSHA256: String
    var целевойSHA256: String
    var хэшНеАдресныхБайтов: String
    var нормализованныйSHA256: String
    var строк: Int
    var локальныхАдресов: Int
    var различныхЦелей: Int
    var изменённыхАдресов: Int
    var различныхИзменённыхАдресов: Int
    var якоряПроверены = false
}

enum ДоказательствоАдреснойКопииДокументации {
    static func построить(исходный: УзелОбщейМиграции, целевой: УзелОбщейМиграции,
        отображения: [СтрокаОбщегоОтображения], пространство: Set<Data>) throws -> ДоказательствоКопииДокументации {
        try ПримитивыДокументации.требовать(исходный.вид == .файл && целевой.вид == .файл && исходный.режим == целевой.режим
            && !исходный.дословный && !целевой.дословный && (исходный.путь as NSString).pathExtension.lowercased() == "md"
            && (целевой.путь as NSString).pathExtension.lowercased() == "md", "не-сопоставимая-адресная-копия")
        func адреса(_ узел: УзелОбщейМиграции) throws -> ([Data], [Data]) {
            let документ = ДокументСсылокПакета(путь: узел.путь, байты: узел.байты, sha256: хэшПутей(узел.байты))
            let перечень = РешательСсылокПакета.перечислитьАдреса(документ)
            try ПримитивыДокументации.требовать(перечень.обходЗавершён && перечень.синтаксисПолностьюРаспознан
                && перечень.ошибки.isEmpty, "не-полностью-разобрана-адресная-копия")
            let диапазоны = перечень.узлы.compactMap(\.адрес).sorted { $0.lowerBound < $1.lowerBound }
            var конец = 0, адреса: [Data] = [], прочее: [Data] = []
            for диапазон in диапазоны {
                try ПримитивыДокументации.требовать(диапазон.lowerBound >= конец && диапазон.upperBound <= узел.байты.count, "неверные-диапазоны-адресов")
                прочее.append(узел.байты.subdata(in: конец..<диапазон.lowerBound))
                адреса.append(узел.байты.subdata(in: диапазон)); конец = диапазон.upperBound
            }
            прочее.append(узел.байты.subdata(in: конец..<узел.байты.count))
            return (адреса, прочее)
        }
        let левая = try адреса(исходный), правая = try адреса(целевой)
        try ПримитивыДокументации.требовать(левая.0.count == правая.0.count && левая.1 == правая.1, "изменилась-не-URI-часть-копии")
        let конечное = Set(пространство.map { Data(ПрофильОбъединенияДокументации.назначение(String(decoding: $0, as: UTF8.self)).utf8) })
        let входы = [исходный, целевой].map { ДокументСсылокПакета(путь: $0.путь, байты: $0.байты, sha256: хэшПутей($0.байты)) }
        let результаты = try РешательСсылокПакета.разрешитьМиграцию(документы: входы, ожидаемыеПути: входы.map(\.путь),
            отображения: отображения, исходныеПути: пространство, конечныеПути: конечное)
        guard let первый = результаты[исходный.путь], let второй = результаты[целевой.путь] else {
            throw ОтказАдаптераДокументации.условие("неполный-результат-адресной-копии")
        }
        try ПримитивыДокументации.требовать(первый.полнотаПроверена && второй.полнотаПроверена
            && первый.байтыПосле == второй.байтыПосле
            && первый.целиПосле.map({ Data($0.utf8) }) == второй.целиПосле.map({ Data($0.utf8) }), "разные-разрешённые-цели-или-суффиксы-копии")
        let изменения = zip(левая.0, правая.0).filter { $0.0 != $0.1 }
        let строки = исходный.байты.filter { $0 == 10 }.count + (исходный.байты.last == 10 ? 0 : 1)
        let строкиЦели = целевой.байты.filter { $0 == 10 }.count + (целевой.байты.last == 10 ? 0 : 1)
        try ПримитивыДокументации.требовать(строки == строкиЦели, "изменилось-число-строк-копии")
        return .init(исходный: исходный.путь, целевой: целевой.путь, исходныйSHA256: хэшПутей(исходный.байты),
            целевойSHA256: хэшПутей(целевой.байты), хэшНеАдресныхБайтов: try хэшПутей(байтыПлана(левая.1)),
            нормализованныйSHA256: хэшПутей(первый.байтыПосле), строк: строки,
            локальныхАдресов: первый.целиПосле.count, различныхЦелей: Set(первый.целиПосле.map { Data($0.utf8) }).count,
            изменённыхАдресов: изменения.count, различныхИзменённыхАдресов: Set(изменения.map { $0.0 }).count)
    }
}

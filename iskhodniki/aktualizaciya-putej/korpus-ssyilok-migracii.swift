import Foundation

enum РольДокументаКорпуса: String, Codable, Sendable { case действующий, дословный, неизвестный }
enum СостояниеДокументаКорпуса: String, Codable, Sendable { case провереныПути, сохраненыБайты, неПроверено }

struct ДокументКорпусаМиграции: Sendable {
    var путь: String
    var байты: Data
    var роль: РольДокументаКорпуса
    var основаниеРоли: String
    var режим = "100644"
}

struct ОжидаемыйДокументКорпуса: Codable, Equatable, Sendable {
    var путь: String
    var хэш: String
    var режим = "100644"
}

struct РезультатДокументаКорпуса: Codable, Equatable, Sendable {
    var исходныйПуть: String
    var будущийПуть: String
    var исходныйХэш: String
    var режим: String
    var роль: РольДокументаКорпуса
    var основаниеРоли: String
    var состояние: СостояниеДокументаКорпуса
    var будущиеБайты: Data?
    var целиПосле: [String]
    var первыйОтказ: String?
}

struct ПланКорпусаСсылок: Codable, Equatable, Sendable {
    var схема = "fum.корпус-ссылок-общей-миграции.1"
    var основа: ОсноваОбщейМиграции
    var источникОжидаемогоКорпуса: String
    var хэшОжидаемогоКорпуса: String
    var хэшПространств: String
    var хэшРолей: String = ""
    var документы: [РезультатДокументаКорпуса]
    var препятствия: [ПрепятствиеОбщейМиграции]
    var полнотаУчёта = false
    var полнотаПутейПриПереданныхРолях = false
    var якоряИЗапросыПроверены = false
    var готовностьКонтекста = false
    var применениеРазрешено = false
}

enum КорпусСсылокМиграции {
    static func построить(основа: ОсноваОбщейМиграции, ожидаемаяОснова: ОсноваОбщейМиграции,
        документы: [ДокументКорпусаМиграции], ожидаемые: [ОжидаемыйДокументКорпуса], источникОжидаемого: String,
        отображения: [СтрокаОбщегоОтображения], исходныеПути: Set<Data>, конечныеПути: Set<Data>, исключённыеБезЗамены: Set<Data> = []) throws -> ПланКорпусаСсылок {
        _ = try ОбщийПланировщикПутей.построить(основа: основа, ожидаемаяОснова: ожидаемаяОснова, узлы: [], корни: [])
        guard !источникОжидаемого.isEmpty, документы.count <= 8192, ожидаемые.count <= 8192 else { throw ОтказКорпусаСсылок.условие("неверная-граница-корпуса") }
        let упорядоченные = документы.sorted { порядокПутей($0.путь, $1.путь) }
        let ожидаемыеПоПути = ожидаемые.sorted { порядокПутей($0.путь, $1.путь) }
        let пути = упорядоченные.map { Data($0.путь.utf8) }, ожидаемыеПути = ожидаемыеПоПути.map { Data($0.путь.utf8) }
        guard пути == ожидаемыеПути, Set(пути).count == пути.count else { throw ОтказКорпусаСсылок.условие("неполный-или-повторный-корпус") }
        var объём = 0
        for (документ, ожидание) in zip(упорядоченные, ожидаемыеПоПути) {
            try ИменаПутей.проверитьПуть(документ.путь)
            guard ИменаПутей.компоненты(документ.путь).first != "Proyekcii", исходныеПути.contains(Data(документ.путь.utf8)),
                  документ.режим == ожидание.режим, ["100644", "100755"].contains(документ.режим),
                  ОбщийПланировщикПутей.хэш(документ.байты) == ожидание.хэш,
                  документ.байты.count <= 134_217_728 - объём else { throw ОтказКорпусаСсылок.условие("дрейф-или-неверный-документ-корпуса") }
            объём += документ.байты.count
        }
        for пространство in [исходныеПути, конечныеПути] {
            var алиасы: [Data: Data] = [:]
            for ключ in пространство {
                guard let путь = String(data: ключ, encoding: .utf8) else { throw ОтказКорпусаСсылок.условие("не-UTF8-пространство") }
                try ИменаПутей.проверитьПуть(путь)
                var префикс = ""
                for часть in ИменаПутей.компоненты(путь) {
                    префикс += (префикс.isEmpty ? "" : "/") + часть
                    let алиас = ИменаПутей.ключКоллизии(префикс), точный = Data(префикс.utf8)
                    if let прежний = алиасы[алиас], прежний != точный { throw ОтказКорпусаСсылок.условие("алиасы-компонентов-пространства") }
                    алиасы[алиас] = точный
                }
            }
        }
        guard исключённыеБезЗамены.isSubset(of: исходныеПути), исключённыеБезЗамены.isDisjoint(with: конечныеПути) else { throw ОтказКорпусаСсылок.условие("неверные-исключённые-цели") }
        var карта: [Data: String] = [:]
        for пара in отображения {
            try ИменаПутей.проверитьПуть(пара.исходный); try ИменаПутей.проверитьПуть(пара.целевой)
            guard карта.updateValue(пара.целевой, forKey: Data(пара.исходный.utf8)) == nil,
                  исходныеПути.contains(Data(пара.исходный.utf8)), конечныеПути.contains(Data(пара.целевой.utf8)),
                  !исключённыеБезЗамены.contains(Data(пара.исходный.utf8)) else { throw ОтказКорпусаСсылок.условие("неверное-отображение-корпуса") }
        }
        var результаты: [РезультатДокументаКорпуса] = [], препятствия: [ПрепятствиеОбщейМиграции] = []
        let отсортированныеОтображения = отображения.sorted { порядокПутей($0.исходный, $1.исходный) }
        for документ in упорядоченные {
            let будущийПуть = карта[Data(документ.путь.utf8)] ?? документ.путь
            var результат = РезультатДокументаКорпуса(исходныйПуть: документ.путь, будущийПуть: будущийПуть, исходныйХэш: ОбщийПланировщикПутей.хэш(документ.байты), режим: документ.режим,
                роль: документ.роль, основаниеРоли: документ.основаниеРоли, состояние: .неПроверено, будущиеБайты: nil, целиПосле: [], первыйОтказ: nil)
            if !конечныеПути.contains(Data(будущийПуть.utf8)) || исключённыеБезЗамены.contains(Data(документ.путь.utf8)) {
                результат.первыйОтказ = "нет-будущего-документа"
            } else if документ.основаниеРоли.isEmpty { результат.первыйОтказ = "нет-основания-роли" }
            else {
                switch документ.роль {
                case .неизвестный: результат.первыйОтказ = "неизвестная-роль-документа"
                case .дословный:
                    результат.будущиеБайты = Data(документ.байты); результат.состояние = .сохраненыБайты
                case .действующий:
                    if ИменаПутей.имеетПрефикс(документ.путь, "Источники/") { результат.первыйОтказ = "конфликт-роли-с-защитой-источника" }
                    else if ИменаПутей.имеетПрефикс(документ.путь, "Журнал/") && (документ.путь as NSString).lastPathComponent == "запрос.md" {
                        результат.первыйОтказ = "не-подтверждён-синтаксический-охват-Журнала"
                    } else if String(data: документ.байты, encoding: .utf8)?.contains("Текст запроса") == true {
                        // Пока роли поддиапазонов не связаны с источником,
                        // возможная защитная секция требует отдельной проверки.
                        результат.первыйОтказ = "не-подтверждена-защита-поддиапазонов"
                    } else {
                        do {
                            let вход = ДокументСсылокПакета(путь: документ.путь, байты: документ.байты, sha256: результат.исходныйХэш)
                            let проверенные = try РешательСсылокПакета.разрешитьМиграцию(документы: [вход], ожидаемыеПути: [документ.путь], отображения: отсортированныеОтображения,
                                исходныеПути: исходныеПути, конечныеПути: конечныеПути, удалённыеПути: исключённыеБезЗамены)
                            guard let проверка = проверенные[документ.путь], проверка.полнотаПроверена else { throw ОтказКорпусаСсылок.условие("неполный-результат-решателя") }
                            результат.будущиеБайты = проверка.байтыПосле; результат.целиПосле = проверка.целиПосле; результат.состояние = .провереныПути
                        } catch ОтказСсылокПакета.условие(let причина) { результат.первыйОтказ = причина }
                        catch ОтказКорпусаСсылок.условие(let причина) { результат.первыйОтказ = причина }
                        catch { результат.первыйОтказ = "неожиданный-тип-ошибки-решателя: " + String(reflecting: type(of: error)) }
                    }
                }
            }
            if let отказ = результат.первыйОтказ { препятствия.append(.init(код: отказ, пути: [документ.путь])) }
            результаты.append(результат)
        }
        let группы = Dictionary(grouping: результаты, by: { Data($0.будущийПуть.utf8) })
        for группа in группы.values where группа.count > 1 {
            let исходные = группа.map(\.исходныйПуть).sorted(by: порядокПутей)
            if группа.contains(where: { $0.состояние == .неПроверено }) { препятствия.append(.init(код: "не-замкнута-группа-корпуса", пути: исходные)) }
            else if Set(группа.map(\.роль)).count > 1 { препятствия.append(.init(код: "разные-роли-назначения", пути: исходные)) }
            else if let первый = группа.first, группа.contains(where: { $0.режим != первый.режим || $0.будущиеБайты != первый.будущиеБайты || $0.целиПосле.map({ Data($0.utf8) }) != первый.целиПосле.map({ Data($0.utf8) }) }) {
                препятствия.append(.init(код: "разные-результаты-назначения", пути: исходные))
            }
        }
        препятствия.sort { $0.код == $1.код ? порядокПутей($0.пути.joined(separator: "\0"), $1.пути.joined(separator: "\0")) : порядокПутей($0.код, $1.код) }
        let пространства = ПространстваКорпуса(исходные: исходныеПути.sorted { $0.lexicographicallyPrecedes($1) }, конечные: конечныеПути.sorted { $0.lexicographicallyPrecedes($1) },
            отображения: отсортированныеОтображения, исключённые: исключённыеБезЗамены.sorted { $0.lexicographicallyPrecedes($1) })
        let роли = результаты.map { НазначениеРолиКорпуса(путь: $0.исходныйПуть, хэш: $0.исходныйХэш, роль: $0.роль, основание: $0.основаниеРоли) }
        var план = try ПланКорпусаСсылок(основа: основа, источникОжидаемогоКорпуса: источникОжидаемого,
            хэшОжидаемогоКорпуса: хэш(ожидаемыеПоПути), хэшПространств: хэш(пространства), документы: результаты, препятствия: препятствия)
        план.хэшРолей = try хэш(роли); план.полнотаУчёта = true; план.полнотаПутейПриПереданныхРолях = препятствия.isEmpty
        return план
    }

    private static func хэш<Значение: Encodable>(_ значение: Значение) throws -> String {
        let кодировщик = JSONEncoder(); кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try ОбщийПланировщикПутей.хэш(кодировщик.encode(значение))
    }
}

enum ОтказКорпусаСсылок: Error, Equatable { case условие(String) }
private struct ПространстваКорпуса: Codable {
    var исходные: [Data]
    var конечные: [Data]
    var отображения: [СтрокаОбщегоОтображения]
    var исключённые: [Data]
}
private struct НазначениеРолиКорпуса: Codable {
    var путь: String
    var хэш: String
    var роль: РольДокументаКорпуса
    var основание: String
}

enum ПроверкаОкнаКандидатов {
    private static func требовать(_ условие: Bool, _ код: String) throws {
        if !условие { throw ОтказСсылокПакета.условие(код) }
    }
    private static func хэшВерный(_ значение: String) -> Bool {
        значение.utf8.count == 64 && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
    private static func номерВерный(_ значение: String) -> Bool {
        значение.utf8.count == 36 && UUID(uuidString: значение)?.uuidString.lowercased() == значение
    }
    private static func проверитьОпоры(_ о: ОпорыОкнаДиагностики) throws {
        try требовать(номерВерный(о.коллекция) && [о.хэшПрофиля, о.хэшИсточникаПроизводителя, о.хэшСредыПроизводителя].allSatisfy(хэшВерный), "неверные-опоры-окна")
    }
    private static func поляОпор(_ о: ОпорыОкнаДиагностики) -> [(String, ЗначениеПакета)] {
        [("коллекция", .строка(о.коллекция)), ("хэшПрофиля", .строка(о.хэшПрофиля)),
         ("хэшИсточникаПроизводителя", .строка(о.хэшИсточникаПроизводителя)), ("хэшСредыПроизводителя", .строка(о.хэшСредыПроизводителя))]
    }
    private static func полеАртефакта(_ а: АртефактКандидатов) throws -> ЗначениеПакета {
        try ИменаПутей.проверитьПуть(а.путь)
        try требовать(а.путь.utf8.allSatisfy { (97...122).contains($0) || (48...57).contains($0) || [45, 46, 47].contains($0) }
            && хэшВерный(а.хэш) && (0...33_554_432).contains(а.размер), "неверная-ссылка-окна")
        return .массив([.строка(а.путь), .строка(а.хэш), .число(а.размер), .строка(а.роль.rawValue)])
    }
    private static func необязательныйХэш(_ хэш: String?) -> ЗначениеПакета {
        .массив(хэш.map { [.строка($0)] } ?? [])
    }
    static func байтыМанифеста(_ м: МанифестОкнаДиагностики) throws -> Data {
        try проверитьОпоры(м.опоры)
        try требовать(номерВерный(м.окно) && хэшВерный(м.хэшПлана) && хэшВерный(м.хэшНамерения)
            && (м.хэшПредыдущейТочки.map(хэшВерный) ?? true) && (0..<8192).contains(м.перваяПорция)
            && (1...4).contains(м.числоПорций) && (1...1024).contains(м.результаты.count), "ранний-предел-манифеста-окна")
        var строки: [ЗначениеПакета] = []
        for ссылка in м.результаты {
            let з = ссылка.заголовок
            try требовать((0..<8192).contains(з.номерДокумента) && (1...1024).contains(з.байтыПути) && (0...33_554_432).contains(з.размерДокумента)
                && [з.хэшПути, з.хэшДокумента, з.хэшПлана, з.хэшКонтекста, з.хэшОжидания, з.хэшФизическогоСнимка, з.хэшСобственногоИсточника].allSatisfy(хэшВерный), "неверный-заголовок-результата")
            строки.append(.массив([.число(з.номерДокумента), .строка(з.хэшПути), .число(з.байтыПути), .строка(з.хэшДокумента),
                .число(з.размерДокумента), .строка(з.хэшПлана), .строка(з.хэшКонтекста), .строка(з.хэшОжидания),
                .строка(з.хэшФизическогоСнимка), .строка(з.хэшСобственногоИсточника), try полеАртефакта(ссылка.артефакт)]))
        }
        return try ФорматированныйПисательПакета.записать(.объект([("схема", .строка("fum.манифест-окна-кандидатов.1"))] + поляОпор(м.опоры) + [
            ("окно", .строка(м.окно)), ("хэшПлана", .строка(м.хэшПлана)), ("хэшНамерения", .строка(м.хэшНамерения)),
            ("хэшПредыдущейТочки", необязательныйХэш(м.хэшПредыдущейТочки)), ("перваяПорция", .число(м.перваяПорция)),
            ("числоПорций", .число(м.числоПорций)), ("результаты", .массив(строки))]), предел: 1_048_576)
    }
    private static func содержит(_ текущий: УчтённаяКоллекцияКандидатов, прежний: УчтённаяКоллекцияКандидатов) throws {
        try требовать(текущий.идентификатор == прежний.идентификатор && текущий.хэшПрофиля == прежний.хэшПрофиля
            && текущий.предел == прежний.предел && !текущий.содержитНеизвестныеОстатки, "сброшены-опоры-учёта-окна")
        let факты = Dictionary(uniqueKeysWithValues: текущий.артефакты.map { (Data($0.путь.utf8), $0) })
        for а in прежний.артефакты { try требовать(факты[Data(а.путь.utf8)] == а, "утрачен-прежний-артефакт-окна") }
    }
    static func проверить(план: ПланПорцийКандидатов, опоры: ОпорыОкнаДиагностики,
        предыдущая: ПредыдущаяГраницаДиагностики, история: [ПопыткаОкнаДиагностики], учёт: УчтённаяКоллекцияКандидатов,
        манифест: МанифестОкнаДиагностики, байтыМанифеста: Data, артефактМанифеста: АртефактКандидатов) throws -> ПроверенноеСтруктурноеОкно {
        try проверитьОпоры(опоры)
        try требовать(история.count <= 8192 && !история.isEmpty && !учёт.содержитНеизвестныеОстатки
            && учёт.идентификатор == опоры.коллекция && учёт.хэшПрофиля == опоры.хэшПрофиля
            && байтыМанифеста.count <= 1_048_576, "неверная-коллекция-окна")
        var номера: Set<String> = []
        for попытка in история {
            try требовать(номерВерный(попытка.окно) && номера.insert(попытка.окно).inserted, "дубль-или-неверный-номер-попытки")
            guard case .обычныйВыход(let терминал) = попытка.терминал else { throw ОтказСсылокПакета.условие("неизвестная-или-незавершённая-попытка") }
            try проверитьОпоры(терминал.опоры)
            _ = try полеАртефакта(попытка.намерение)
            _ = try полеАртефакта(терминал.артефакт)
            try требовать(терминал.кодВыхода == 0 && терминал.окно == попытка.окно && терминал.опоры == опоры
                && хэшВерный(терминал.хэшМанифеста) && хэшВерный(терминал.хэшНамерения)
                && терминал.хэшНамерения == попытка.намерение.хэш, "неверный-терминал-окна")
        }
        let канонические = try Self.байтыМанифеста(манифест)
        var первая = 0, документ = 0, прежняяИстория: [ПопыткаОкнаДиагностики] = [], прежниеПути: Set<Data> = []
        var хэшПредыдущейТочки: String?
        switch предыдущая {
        case .начало: break
        case .голова(let голова):
            try требовать(голова.окно.опоры == опоры && голова.окно.хэшПлана == план.хэшСостава, "чужая-голова-окна")
            try содержит(учёт, прежний: голова.учёт)
            первая = голова.окно.следующаяПорция; документ = голова.окно.следующийДокумент
            прежняяИстория = голова.окно.история; хэшПредыдущейТочки = голова.контрольнаяТочка.хэш
            прежниеПути = Set(голова.учёт.артефакты.map { Data($0.путь.utf8) })
        }
        let м = манифест
        try требовать(история.count == прежняяИстория.count + 1 && Array(история.dropLast()) == прежняяИстория,
            "история-не-является-единственным-продолжением")
        let попытка = история[история.count - 1]
        try требовать(м.опоры == опоры && м.хэшПлана == план.хэшСостава && м.окно == попытка.окно
            && м.хэшНамерения == попытка.намерение.хэш && м.хэшПредыдущейТочки == хэшПредыдущейТочки
            && м.перваяПорция == первая && (1...4).contains(м.числоПорций)
            && первая >= 0 && первая < план.шаги.count && м.числоПорций <= план.шаги.count - первая, "дрейф-опор-или-границы-окна")
        let следующая = первая + м.числоПорций
        for шаг in план.шаги[первая..<следующая] {
            try требовать(шаг.допускаетОбход && шаг.начало == документ && шаг.конец > документ, "разрыв-или-недопущенная-порция-окна")
            документ = шаг.конец
        }
        let начало = план.шаги[первая].начало
        try требовать(м.результаты.count == документ - начало, "неполный-набор-результатов-окна")
        let факты = Dictionary(uniqueKeysWithValues: учёт.артефакты.map { (Data($0.путь.utf8), $0) })
        var новыеПути: Set<Data> = []
        func включить(_ а: АртефактКандидатов, _ роль: РольАртефактаКандидатов) throws {
            _ = try полеАртефакта(а)
            let ключ = Data(а.путь.utf8)
            try требовать(а.роль == роль && факты[ключ] == а && !прежниеПути.contains(ключ)
                && новыеПути.insert(ключ).inserted, "неучтённая-или-повторная-ссылка-окна")
        }
        try включить(попытка.намерение, .управление)
        try включить(артефактМанифеста, .управление)
        guard case .обычныйВыход(let терминал) = попытка.терминал else { throw ОтказСсылокПакета.условие("нет-терминала-окна") }
        try включить(терминал.артефакт, .управление)
        for (смещение, ссылка) in м.результаты.enumerated() {
            let ожидаемая = try план.ожидаемаяЗапись(начало + смещение), з = ссылка.заголовок, д = ожидаемая.документ
            try требовать(з.номерДокумента == ожидаемая.номер && з.хэшПути == хэшПутей(Data(д.путь.utf8)) && з.байтыПути == д.путь.utf8.count
                && з.хэшДокумента == д.хэш && з.размерДокумента == д.размер && з.хэшПлана == ожидаемая.хэшПлана
                && з.хэшКонтекста == ожидаемая.опоры.контекст && з.хэшОжидания == ожидаемая.опоры.ожидание
                && з.хэшФизическогоСнимка == ожидаемая.опоры.физическийСнимок && з.хэшСобственногоИсточника == ожидаемая.опоры.собственныйИсточник,
                "результат-вне-записи-плана-окна")
            try включить(ссылка.артефакт, .результат)
        }
        for а in учёт.артефакты where !прежниеПути.contains(Data(а.путь.utf8)) && !новыеПути.contains(Data(а.путь.utf8)) {
            try требовать(а.роль == .журнал || (первая == 0 && а.роль == .основа), "посторонний-артефакт-вне-цепи-окна")
        }
        try требовать(байтыМанифеста == канонические && артефактМанифеста.размер == канонические.count
            && артефактМанифеста.хэш == хэшПутей(канонические) && терминал.хэшМанифеста == артефактМанифеста.хэш,
            "дрейф-байтов-манифеста-окна")
        let точка = try ФорматированныйПисательПакета.записать(.объект([("схема", .строка("fum.контрольная-точка-окна-кандидатов.1"))] + поляОпор(опоры) + [
            ("окно", .строка(м.окно)), ("хэшПлана", .строка(план.хэшСостава)), ("следующаяПорция", .число(следующая)),
            ("следующийДокумент", .число(документ)), ("хэшПредыдущейТочки", необязательныйХэш(хэшПредыдущейТочки)),
            ("учётДоТочки", .строка(учёт.хэшСостава)), ("намерение", try полеАртефакта(попытка.намерение)),
            ("манифест", try полеАртефакта(артефактМанифеста)), ("терминал", try полеАртефакта(терминал.артефакт))]), предел: 16_384)
        return .init(опоры: опоры, хэшПлана: план.хэшСостава, следующаяПорция: следующая, следующийДокумент: документ,
            учёт: учёт, байтыКонтрольнойТочки: точка, история: история)
    }
    static func связать(_ окно: ПроверенноеСтруктурноеОкно, контрольнаяТочка: АртефактКандидатов,
        учёт: УчтённаяКоллекцияКандидатов) throws -> ГоловаПроверенногоОкна {
        _ = try полеАртефакта(контрольнаяТочка)
        try содержит(учёт, прежний: окно.учёт)
        try требовать(контрольнаяТочка.роль == .управление && контрольнаяТочка.размер == окно.байтыКонтрольнойТочки.count
            && контрольнаяТочка.хэш == хэшПутей(окно.байтыКонтрольнойТочки)
            && !окно.учёт.артефакты.contains { Data($0.путь.utf8) == Data(контрольнаяТочка.путь.utf8) }
            && учёт.артефакты.count == окно.учёт.артефакты.count + 1
            && учёт.артефакты.contains(контрольнаяТочка), "неверная-контрольная-точка-окна")
        return .init(окно: окно, контрольнаяТочка: контрольнаяТочка, учёт: учёт)
    }
}

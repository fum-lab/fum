import Foundation

struct УпорядоченныйНаборПутей<Элемент: Hashable> {
    private(set) var значения: [Элемент] = []
    private var индекс: Set<Элемент> = []

    mutating func добавить(_ элемент: Элемент) {
        if индекс.insert(элемент).inserted { значения.append(элемент) }
    }
}

enum ПостроительПланаПутей {
    static func построить(_ снимок: СнимокПутей, отображения: [ОтображениеПути],
                          контекст: КонтекстПутей, хэшОтображения: String,
                          соседи: [Data: [Data]] = [:]) throws -> ПланПутей {
        var накопитель = УпорядоченныйНаборПутей<ПрепятствиеПути>()
        func препятствие(_ код: String, _ пути: [String]) {
            let новое = ПрепятствиеПути(код: код, пути: пути.sorted(by: порядокПутей))
            накопитель.добавить(новое)
        }
        if снимок.индекс_изменён { препятствие("изменённый-индекс", []) }
        if контекст.владелец.isEmpty || контекст.писатель != контекст.владелец {
            препятствие("неподтверждённый-писатель", [])
        }
        for занятый in контекст.занятые_пути { try ИменаПутей.проверитьПуть(занятый.путь) }
        var источники: [Data: ОтображениеПути] = [:]
        var исходныеКлючи: [Data: Data] = [:]
        var целевыеКлючи: [Data: String] = [:]
        var исключения: [ИсключениеИмени] = []
        var итог: [ОтображениеПути] = []
        let записи = Dictionary(снимок.записи.map { (Data($0.путь.utf8), $0) }, uniquingKeysWith: { первое, _ in первое })
        guard записи.count == снимок.записи.count else { throw ОшибкаПутей.отказ("Повтор exact-пути снимка") }
        for пара in отображения.sorted(by: { порядокПутей($0.исходный, $1.исходный) }) {
            try ИменаПутей.проверитьПуть(пара.исходный)
            let ключ = Data(пара.исходный.utf8)
            guard источники[ключ] == nil, let запись = записи[ключ] else {
                throw ОшибкаПутей.отказ("Отображение не совпало с конечным инвентарём")
            }
            guard ["файл", "каталог", "symlink", "внешняя-зависимость", "производный-слой"].contains(запись.тип) else {
                throw ОшибкаПутей.отказ("Неизвестный тип инвентаря")
            }
            if запись.тип == "symlink" { препятствие("символическая-ссылка", [пара.исходный]) }
            if запись.тип == "внешняя-зависимость" || запись.тип == "производный-слой" {
                препятствие("отдельный-владелец-области", [пара.исходный])
            }
            let неподвижный = запись.тип == "внешняя-зависимость" || запись.тип == "производный-слой"
            if неподвижный, Data(пара.исходный.utf8) != Data(пара.целевой.utf8) {
                throw ОшибкаПутей.отказ("Нельзя переименовать внешнюю или производную границу")
            }
            let исключение = запись.тип == "файл" ? ИменаПутей.исключение(пара.исходный) : nil
            let части = пара.целевой.split(separator: "/", omittingEmptySubsequences: false).map(String.init)
            try ИменаПутей.проверитьПуть(пара.целевой)
            if let исключение, части.last.map({ Data($0.utf8) }) != Data(исключение.имя.utf8) {
                throw ОшибкаПутей.отказ("Mapping меняет фиксированное имя инструмента")
            }
            var нормальные = try части.enumerated().map { номер, часть in
                if неподвижный { return часть }
                if номер == части.count - 1, let исключение { return исключение.имя }
                return try ИменаПутей.нормализовать(часть)
            }
            guard !нормальные.isEmpty else { throw ОшибкаПутей.отказ("Пустое назначение") }
            if let исключение { исключения.append(исключение); нормальные[нормальные.count - 1] = исключение.имя }
            let целевой = нормальные.joined(separator: "/")
            try ИменаПутей.проверитьПуть(целевой)
            let новая = ОтображениеПути(исходный: пара.исходный, целевой: целевой)
            источники[ключ] = новая
            итог.append(новая)
            let исходныйКлюч = ИменаПутей.ключКоллизии(пара.исходный)
            if let прежний = исходныеКлючи[исходныйКлюч], прежний != ключ {
                препятствие("коллизия-исходных-имён", [String(decoding: прежний, as: UTF8.self), пара.исходный])
            }
            исходныеКлючи[исходныйКлюч] = ключ
            let целевойКлюч = ИменаПутей.ключКоллизии(целевой)
            if let прежний = целевыеКлючи[целевойКлюч] {
                препятствие("коллизия-назначения", [прежний, пара.исходный])
            }
            целевыеКлючи[целевойКлюч] = пара.исходный
            if Data(целевой.utf8) != ключ, ИменаПутей.ключКоллизии(целевой) == исходныйКлюч {
                препятствие("переименование-только-регистра", [пара.исходный, целевой])
            }
            if запись.тип == "каталог", ИменаПутей.вложен(целевой, в: пара.исходный), Data(целевой.utf8) != ключ {
                препятствие("каталог-внутри-себя", [пара.исходный, целевой])
            }
            for занятый in контекст.занятые_пути where занятый.владелец != контекст.писатель {
                let занято = String(decoding: ИменаПутей.ключКоллизии(занятый.путь), as: UTF8.self)
                let исходный = String(decoding: ИменаПутей.ключКоллизии(пара.исходный), as: UTF8.self)
                let новый = String(decoding: ИменаПутей.ключКоллизии(целевой), as: UTF8.self)
                if ИменаПутей.вложен(исходный, в: занято) || ИменаПутей.вложен(новый, в: занято)
                    || ИменаПутей.вложен(занято, в: исходный) || ИменаПутей.вложен(занято, в: новый) {
                    препятствие("чужой-писатель", [пара.исходный])
                }
            }
        }
        guard источники.count == записи.count else { throw ОшибкаПутей.отказ("Неполное отображение инвентаря") }
        var индексыСоседей: [Data: [Data: [Data]]] = [:]
        for пара in итог {
            let исходныйКлюч = Data(пара.исходный.utf8)
            guard Data(пара.целевой.utf8) != исходныйКлюч else { continue }
            let родитель = пара.исходный.split(separator: "/").dropLast().joined(separator: "/")
            let родительскийКлюч = Data(родитель.utf8)
            if индексыСоседей[родительскийКлюч] == nil {
                индексыСоседей[родительскийКлюч] = Dictionary(grouping: соседи[родительскийКлюч] ?? [],
                    by: { ИменаПутей.ключКоллизии(String(decoding: $0, as: UTF8.self)) })
            }
            let имяНазначения = пара.целевой.split(separator: "/").last.map(String.init) ?? ""
            for имя in индексыСоседей[родительскийКлюч]?[ИменаПутей.ключКоллизии(имяНазначения)] ?? [] {
                let чужойПуть = (родитель.isEmpty ? Data() : Data((родитель + "/").utf8)) + имя
                if источники[чужойПуть] == nil { препятствие("занятое-назначение", [пара.исходный, пара.целевой]) }
            }
            if записи[исходныйКлюч]?.тип == "каталог" {
                for имя in соседи[исходныйКлюч] ?? [] {
                    if источники[Data((пара.исходный + "/").utf8) + имя] == nil {
                        препятствие("неполный-перенос-каталога", [пара.исходный])
                    }
                }
            }
        }
        for пара in итог {
            let части = пара.исходный.split(separator: "/")
            if части.count == 1 {
                if пара.целевой.contains("/") { препятствие("несогласованный-родитель", [пара.исходный]) }
            } else {
                let родитель = части.dropLast().joined(separator: "/")
                let ключ = Data(родитель.utf8)
                if записи[ключ]?.тип != "каталог" {
                    препятствие("неполный-родитель", [пара.исходный, родитель])
                } else if let отображение = источники[ключ],
                          Data(отображение.целевой.utf8) != Data(пара.целевой.split(separator: "/").dropLast().joined(separator: "/").utf8) {
                    препятствие("несогласованный-родитель", [пара.исходный, родитель])
                }
            }
        }
        let файлы = Set(итог.filter { записи[Data($0.исходный.utf8)]?.тип == "файл" }.map { Data($0.целевой.utf8) })
        for пара in итог {
            let части = пара.целевой.split(separator: "/")
            if части.count > 1 {
                for глубина in 1..<части.count where файлы.contains(Data(части.prefix(глубина).joined(separator: "/").utf8)) {
                    препятствие("файл-вместо-каталога", [пара.исходный])
                }
            }
        }
        var завершённые: Set<Data> = []
        let переносимые = Dictionary(итог.map { (ИменаПутей.ключКоллизии($0.исходный), $0) }, uniquingKeysWith: { первое, _ in первое })
        for пара in итог {
            var текущий = ИменаПутей.ключКоллизии(пара.исходный)
            var цепь: Set<Data> = []
            while !завершённые.contains(текущий), let следующий = переносимые[текущий], ИменаПутей.ключКоллизии(следующий.целевой) != текущий {
                if !цепь.insert(текущий).inserted {
                    препятствие("цикл-переносов", цепь.map { String(decoding: $0, as: UTF8.self) })
                    break
                }
                текущий = ИменаПутей.ключКоллизии(следующий.целевой)
            }
            завершённые.formUnion(цепь)
        }
        let ветка = контекст.целевая_ветка
        guard ветка.hasPrefix("refs/heads/"), !ветка.contains(".."), !ветка.contains("@{"),
              !ветка.hasSuffix("/"), !ветка.hasSuffix("."), !ветка.contains("//"),
              ветка.split(separator: "/").allSatisfy({ !$0.hasPrefix(".") && !$0.hasSuffix(".lock") }),
              !ветка.unicodeScalars.contains(where: { $0.value <= 32 || $0.value == 127 || "~^:?*[\\".unicodeScalars.contains($0) }) else {
            throw ОшибкаПутей.отказ("Недопустимый полный ref")
        }
        let переносимаяВетка = String(decoding: ИменаПутей.ключКоллизии(ветка), as: UTF8.self)
        for прежняя in контекст.ветки where Data(прежняя.utf8) != Data(ветка.utf8) {
            let переносимаяПрежняя = String(decoding: ИменаПутей.ключКоллизии(прежняя), as: UTF8.self)
            if ИменаПутей.вложен(переносимаяВетка, в: переносимаяПрежняя) || ИменаПутей.вложен(переносимаяПрежняя, в: переносимаяВетка) {
                препятствие("конфликт-префикса-ref", [прежняя, ветка])
            }
        }
        var препятствия = накопитель.значения
        препятствия.sort { порядокПутей($0.код + $0.пути.joined(separator: "/"), $1.код + $1.пути.joined(separator: "/")) }
        var полныйСнимок = снимок
        полныйСнимок.записи.sort { порядокПутей($0.путь, $1.путь) }
        return try ПланПутей(корень: контекст.корень, владелец: контекст.владелец, ветка: ветка, писатель: контекст.писатель, снимок: полныйСнимок,
            снимок_sha256: снимок.подпись(), отображение_sha256: хэшОтображения,
            отображения: итог, исключения: исключения, препятствия: препятствия)
    }
}

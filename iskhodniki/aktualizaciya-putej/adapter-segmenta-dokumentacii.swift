import Foundation
import Darwin
import КонтейнерНаблюдений

// Test target импортирует только свой АктуализацияПутей; дополнительная
// Package dependency тестов для fault-injection не требуется.
typealias ФайловыеОперацииЖурналаДокументации = ФайловыеОперации

struct РезервФайлаДокументации: Codable, Equatable, Sendable {
    var имя: String
    var байт: Int
    var sha256: String
    var режим: UInt32
}
struct РезервШагаДокументации: Codable, Equatable, Sendable {
    var номер: Int
    var файлы: [РезервФайлаДокументации]
}
struct СвидетельствоИндексаДокументации: Codable, Equatable, Sendable {
    var номер: Int
    var шагSHA256: String
    var индексSHA256: String
    var режимИндекса: UInt32
}
private struct НамерениеШагаДокументации: Codable, Equatable {
    var номер: Int
    var шагSHA256: String
}
private struct МаркерЖурналаДокументации: Codable, Equatable {
    var схема = "fum.постоянный-слот-документации.2"
    var пространство: String
    var планSHA256: String
    var пакетSHA256: String
}

// Единственное backing storage — существующий Сегмент. Постоянное место
// определяется физическим worktree, а не UUID попытки или новым SHA плана.
final class СегментныйЖурналДокументации: ЖурналКонечногоПакетаДокументации {
    private let пакет: ПакетИсполненияДокументации
    private let байтыПакета: Data
    private let допуск: ДопускИсполненияДокументации
    private let операции: ФайловыеОперации
    private var сегмент: Сегмент?
    private var доступен = false
    private var открыт = false
    private var ожидаемыйШаг: Int?
    var номерНамерения: Int? { ожидаемыйШаг }
    private(set) var подтверждённыйПрефикс = 0
    private(set) var индексы: [Int: СвидетельствоИндексаДокументации] = [:]
    private(set) var резервы: [Int: РезервШагаДокументации] = [:]
    var снятьСвидетельство: ((Int) throws -> СвидетельствоИндексаДокументации)?
    var послеПодтверждения: ((Int) throws -> Void)?
    let пространство: String
    let хэшПлана: String
    var каталогСлота: URL { URL(fileURLWithPath: допуск.кореньХранилища).appendingPathComponent(пространство) }

    init(пакет: ПакетИсполненияДокументации, допуск: ДопускИсполненияДокументации,
        операции: ФайловыеОперации = .системные) throws {
        self.пакет = пакет; self.допуск = допуск; self.операции = операции
        байтыПакета = try байтыПлана(пакет); хэшПлана = try хэшПутей(байтыПлана(пакет.план))
        пространство = хэшПутей(Data((пакет.корень + "\0" + пакет.каталогGit).utf8))
        try ПримитивыДокументации.требовать(хэшПутей(байтыПакета) == допуск.пакетSHA256
            && допуск.физическийКорень == пакет.корень && !допуск.источникРешения.isEmpty
            && !пакет.времяЖурнала.isEmpty && пакет.времяЖурнала.utf8.count <= 128, "не-связан-допуск-журнала")
        try Self.проверитьЁмкость(байтПакета: байтыПакета.count, шагов: пакет.план.шаги.count)
    }
    deinit { закрыть() }

    static func проверитьЁмкость(байтПакета: Int, шагов: Int) throws {
        // Пакет + intent/receipt/reserve каждого шага + terminal. Небольшие
        // записи ограничены 4096 байтами; полные payload в них не повторяются.
        // Запас 16384 на обрамление каждой группы превосходит наши bounded
        // JSON headers; сюда входят также фрагменты большой записи пакета.
        try ПримитивыДокументации.требовать((0...1024).contains(шагов) && (0...50_331_648).contains(байтПакета), "предел-пакета-до-арифметики")
        let записей = 3 * шагов + 2
        let фрагментов = (байтПакета + Пределы.фрагмент - 1) / Пределы.фрагмент + 3 * шагов + 1
        let верхняяГраница = байтПакета + записей * 20_480 + фрагментов * 512 + 64
        try ПримитивыДокументации.требовать((0...1024).contains(шагов) && (0...50_331_648).contains(байтПакета)
            && записей <= Пределы.записи && фрагментов <= Пределы.фрагменты
            && верхняяГраница <= Пределы.сегмент && UInt64(байтПакета) <= Пределы.объект, "предел-ёмкости-Segment-до-эффектов")
    }
    private func описание(_ имя: String) -> ОписаниеНаблюдения {
        .init(идентификатор: имя, тип: "fum.документация.пакет.2", версияСхемы: 2,
            источник: пространство, время: пакет.времяЖурнала, спецификация: Data(хэшПлана.utf8))
    }
    private func добавить(_ имя: String, _ данные: Data, большой: Bool = false) throws {
        try ПримитивыДокументации.требовать(доступен && (большой || данные.count <= 4096), "журнал-недоступен-или-предел-записи")
        do {
            guard let сегмент else { throw ОтказАдаптераДокументации.условие("нет-владения-Segment") }
            try ПримитивыДокументации.требовать(try байтыПлана(описание(имя)).count <= 2048, "предел-header-журнала")
            _ = try сегмент.добавить(описание(имя), данные: данные)
        } catch { доступен = false; throw error }
    }
    private func извлечь<Значение: Codable & Equatable>(_ имя: String, _ тип: Значение.Type) throws -> Значение {
        guard let сегмент else { throw ОтказАдаптераДокументации.условие("журнал-закрыт") }
        let данные = try сегмент.извлечь(имя), значение = try JSONDecoder().decode(тип, from: данные)
        try ПримитивыДокументации.требовать(try байтыПлана(значение) == данные, "не-каноническая-запись-журнала")
        return значение
    }
    func открыть(план: Data) throws -> ОткрытиеПакетаДокументации {
        try ПримитивыДокументации.требовать(!открыт && план == байтыПлана(пакет.план), "повтор-open-или-другой-план")
        открыт = true
        let основа = URL(fileURLWithPath: допуск.кореньХранилища)
        try ПримитивыДокументации.абсолютныйКаталог(основа, приватный: true)
        try ПримитивыДокументации.требовать(!основа.pathComponents.contains(".git")
            && основа.path != пакет.корень && !основа.path.hasPrefix(пакет.корень + "/")
            && основа.path != пакет.каталогGit && !основа.path.hasPrefix(пакет.каталогGit + "/"), "runtime-журнал-внутри-worktree-или-Git")
        var предок = основа
        while true {
            try ПримитивыДокументации.требовать(try !ПримитивыДокументации.есть(предок.appendingPathComponent(".git")), "runtime-внутри-Git-предка")
            if предок.path == "/" { break }; предок.deleteLastPathComponent()
        }
        let маркер = основа.appendingPathComponent(пространство + ".json")
        let данныеМаркера = try байтыПлана(МаркерЖурналаДокументации(пространство: пространство,
            планSHA256: хэшПлана, пакетSHA256: хэшПутей(байтыПакета)))
        let естьКаталог = try ПримитивыДокументации.есть(каталогСлота), естьМаркер = try ПримитивыДокументации.есть(маркер)
        let новый = !естьКаталог && !естьМаркер
        if новый {
            try ПримитивыДокументации.требовать(допуск.новыйСлотРазрешён, "нет-допуска-на-новый-постоянный-слот")
            try ПримитивыДокументации.требовать(mkdir(каталогСлота.path, 0o700) == 0, "не-создан-слот")
            try ПримитивыДокументации.синхронизировать(основа, каталог: true)
        } else {
            try ПримитивыДокументации.требовать(естьКаталог && естьМаркер, "частично-потерян-слот-без-повтора")
            try ПримитивыДокументации.требовать(try ПримитивыДокументации.прочитать(маркер, предел: 4096, приватный: true).0 == данныеМаркера,
                "другой-план-в-постоянном-слоте")
            var сведения = stat()
            let имяСегмента = каталогСлота.appendingPathComponent("сегмент.fumobs")
            try ПримитивыДокументации.требовать(lstat(имяСегмента.path, &сведения) == 0 && сведения.st_mode & S_IFMT == S_IFREG
                && сведения.st_mode & 0o7777 == 0o600 && сведения.st_uid == getuid() && сведения.st_nlink == 1, "потерян-или-небезопасен-Segment")
        }
        try ПримитивыДокументации.абсолютныйКаталог(каталогСлота, приватный: true)
        do {
            let открытый = try Сегмент(кореньДанных: каталогСлота, запись: true, создать: новый, операции: операции)
            сегмент = открытый
            try ПримитивыДокументации.требовать(!открытый.естьХвост, "неполный-хвост-без-усечения")
            if новый { try ПримитивыДокументации.записатьНовый(данныеМаркера, маркер) }
            try ПримитивыДокументации.требовать(try ПримитивыДокументации.прочитать(маркер, предел: 4096, приватный: true).0 == данныеМаркера, "маркер-изменён-до-lock")
            доступен = true
            if новый { try добавить("пакет", байтыПакета, большой: true); return .новый }
            try ПримитивыДокументации.требовать(try открытый.извлечь("пакет") == байтыПакета, "потерян-или-заменён-пакет")
            let записи = открытый.записи
            try ПримитивыДокументации.требовать(записи.allSatisfy { $0.описание == описание($0.описание.идентификатор) }, "чужая-схема-записей")
            let имена = записи.map { $0.описание.идентификатор }
            try ПримитивыДокументации.требовать(имена.first == "пакет", "неверное-начало-журнала")
            var позиция = 1
            for шаг in пакет.план.шаги {
                if позиция == имена.count { break }
                if имена[позиция] == "итог" { break }
                try ПримитивыДокументации.требовать(имена[позиция] == "intent-\(шаг.номер)", "дырка-или-неверный-intent")
                let намерение = try извлечь(имена[позиция], НамерениеШагаДокументации.self)
                try ПримитивыДокументации.требовать(намерение == НамерениеШагаДокументации(номер: шаг.номер, шагSHA256: хэшПутей(байтыПлана(шаг))), "другой-шаг-журнала")
                ожидаемыйШаг = шаг.номер; позиция += 1
                if позиция < имена.count, имена[позиция] == "reserve-\(шаг.номер)" {
                    let резерв = try извлечь(имена[позиция], РезервШагаДокументации.self)
                    try проверитьРезерв(резерв); резервы[шаг.номер] = резерв; позиция += 1
                }
                if позиция == имена.count { break }
                try ПримитивыДокументации.требовать(имена[позиция] == "receipt-\(шаг.номер)", "нет-точного-подтверждения")
                let свидетельство = try извлечь(имена[позиция], СвидетельствоИндексаДокументации.self)
                try ПримитивыДокументации.требовать(свидетельство.номер == шаг.номер && свидетельство.шагSHA256 == намерение.шагSHA256
                    && свидетельство.индексSHA256.count == 64 && свидетельство.режимИндекса == пакет.режимИндекса, "неверное-свидетельство-индекса")
                индексы[шаг.номер] = свидетельство; подтверждённыйПрефикс = шаг.номер; ожидаемыйШаг = nil; позиция += 1
            }
            // Exact duplicate заново синхронизирует видимый committed префикс.
            // После ошибки этого fsync экземпляр закрыт; нового append не будет.
            try добавить("пакет", байтыПакета, большой: true)
            if позиция < имена.count {
                try ПримитивыДокументации.требовать(позиция == имена.count - 1 && имена[позиция] == "итог"
                    && подтверждённыйПрефикс == пакет.план.шаги.count && ожидаемыйШаг == nil, "неверный-terminal")
                let итог = try извлечь("итог", КвитанцияОбъединенияДокументации.self)
                try ПримитивыДокументации.требовать(итог.планSHA256 == хэшПлана && итог.исход == .завершено
                    && итог.подтверждённыйПрефикс == подтверждённыйПрефикс && итог.причина == nil, "неверная-terminal-квитанция")
                return .завершённый(итог)
            }
            return .удержанныйПрефикс(подтверждённый: подтверждённыйПрефикс, номерНамерения: ожидаемыйШаг)
        } catch { доступен = false; закрыть(); throw error }
    }
    private func проверитьРезерв(_ резерв: РезервШагаДокументации) throws {
        try ПримитивыДокументации.требовать(резерв.номер > 0 && резерв.номер <= пакет.план.шаги.count
            && (1...2).contains(резерв.файлы.count), "неверный-набор-резервов")
        for файл in резерв.файлы {
            try ПримитивыДокументации.требовать(!файл.имя.contains("/") && файл.имя.contains(".fum-p4-" + String(хэшПлана.prefix(16)))
                && файл.sha256.count == 64 && файл.байт >= 0 && файл.режим <= 0o7777, "неверный-резерв")
        }
    }
    func сохранитьРезерв(_ резерв: РезервШагаДокументации) throws {
        try проверитьРезерв(резерв)
        try ПримитивыДокументации.требовать(ожидаемыйШаг == резерв.номер && резервы[резерв.номер] == nil, "резерв-вне-intent")
        try добавить("reserve-\(резерв.номер)", байтыПлана(резерв)); резервы[резерв.номер] = резерв
    }
    func намерение(_ шаг: ШагПакетаДокументации, хэшПлана: String) throws {
        try ПримитивыДокументации.требовать(хэшПлана == self.хэшПлана && ожидаемыйШаг == nil
            && шаг.номер == подтверждённыйПрефикс + 1 && пакет.план.шаги[подтверждённыйПрефикс] == шаг, "шаг-вне-плана")
        try добавить("intent-\(шаг.номер)", байтыПлана(НамерениеШагаДокументации(номер: шаг.номер, шагSHA256: хэшПутей(байтыПлана(шаг)))))
        ожидаемыйШаг = шаг.номер
    }
    func подтверждение(_ шаг: ШагПакетаДокументации, хэшПлана: String) throws {
        try ПримитивыДокументации.требовать(хэшПлана == self.хэшПлана && ожидаемыйШаг == шаг.номер, "receipt-без-intent")
        guard let снятьСвидетельство else { throw ОтказАдаптераДокументации.условие("нет-concrete-index-свидетельства") }
        let свидетельство = try снятьСвидетельство(шаг.номер)
        try ПримитивыДокументации.требовать(свидетельство.шагSHA256 == хэшПутей(байтыПлана(шаг)) && свидетельство.номер == шаг.номер, "другое-index-свидетельство")
        try добавить("receipt-\(шаг.номер)", байтыПлана(свидетельство))
        индексы[шаг.номер] = свидетельство; подтверждённыйПрефикс = шаг.номер; ожидаемыйШаг = nil
    }
    func очиститьПослеПодтверждения(_ шаг: ШагПакетаДокументации) throws {
        try ПримитивыДокументации.требовать(подтверждённыйПрефикс == шаг.номер && ожидаемыйШаг == nil, "cleanup-до-durable-receipt")
        try послеПодтверждения?(шаг.номер)
    }
    func завершить(_ квитанция: КвитанцияОбъединенияДокументации) throws {
        try ПримитивыДокументации.требовать(ожидаемыйШаг == nil && подтверждённыйПрефикс == пакет.план.шаги.count
            && квитанция.планSHA256 == хэшПлана && квитанция.исход == .завершено
            && квитанция.подтверждённыйПрефикс == подтверждённыйПрефикс && квитанция.причина == nil, "не-полный-terminal")
        try добавить("итог", байтыПлана(квитанция))
    }
    func данныеДляВосстановления() throws -> Data {
        guard let сегмент else { throw ОтказАдаптераДокументации.условие("журнал-закрыт") }
        return try сегмент.извлечь("пакет") // Только экспорт, без truncate/replay/rollback.
    }
    func закрыть() { сегмент?.закрыть(); сегмент = nil; доступен = false }
}

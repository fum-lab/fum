// Источник контракта и точные pins закреплены в port-pereimenovaniya-fajla.json.
struct СостояниеФайлаПереименования: Equatable, Sendable {
    let режим: mode_t
    let устройство: dev_t
    let узел: ino_t
    init(_ адрес: URL) throws {
        var сведения = stat()
        guard lstat(адрес.path, &сведения) == 0 else { throw ОшибкаПутей.отказ("Не прочитан узел переименования") }
        режим = сведения.st_mode; устройство = сведения.st_dev; узел = сведения.st_ino
    }
    var обычный: Bool { режим & S_IFMT == S_IFREG }
    var каталог: Bool { режим & S_IFMT == S_IFDIR }
    var ссылка: Bool { режим & S_IFMT == S_IFLNK }
}

struct ФайлПланаПереименования: Sendable {
    let путь: String
    let байты: Data
    let состояние: СостояниеФайлаПереименования
}

struct ПравкаФайлаПереименования: Sendable {
    let исходный: String
    let итоговый: String
    let байты: Data
    let числоСсылок: Int
    var хэшПосле: String { хэшПутей(байты) }
}

struct ПланПереименованияФайла: Sendable {
    let корень: URL
    let исходный: String
    let целевой: String
    let файлы: [ФайлПланаПереименования]
    let правки: [ПравкаФайлаПереименования]
    let каталоги: [String: СостояниеФайлаПереименования]
    let документы: [String]
    let локальныеЦели: [String]
    let голова: Data
    let ветка: Data
    let статус: Data
    let адресИндекса: URL
    let индекс: Data
    let записиИндекса: Data
    let режимИндекса: mode_t
    let времяСвежести: String?

    func представление(_ режим: String) throws -> Data {
        // Имена полей сохранены по опубликованному Python public_payload.
        let переписанные = правки.map(\.итоговый).sorted(by: порядокПутей)
        var ответ: [String: Any] = [
            "source": исходный, "destination": целевой, "mode": режим,
            "renamed_file": ["source": исходный, "destination": целевой],
            "rewritten_files": переписанные,
            "updated_files": Array(Set(переписанные + [целевой])).sorted(by: порядокПутей),
            "updated_links": правки.reduce(0) { $0 + $1.числоСсылок }
        ]
        if let времяСвежести { ответ["время_свежести"] = времяСвежести }
        return try JSONSerialization.data(withJSONObject: ответ, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) + Data([10])
    }
}

enum ПереименованиеФайла {
    private static var файловаяСистема: FileManager { FileManager() }
    // Один контекст принадлежит ровно одному полному читающему проходу.
    // План не хранит его; каждый fence создаёт новый независимый контекст.
    private final class КонтекстЧтения {
        private struct Каталог {
            let отпечаток: String
            let группы: [String: [String]]
        }
        private var каталоги: [Data: Каталог] = [:]
        private func отпечаток(_ адрес: URL) throws -> String {
            var сведения = stat()
            try требовать(lstat(адрес.path, &сведения) == 0 && сведения.st_mode & S_IFMT == S_IFDIR, "Не реальный каталог читающего прохода")
            return "\(сведения.st_dev):\(сведения.st_ino):\(сведения.st_mode):\(сведения.st_size):\(сведения.st_mtimespec.tv_sec):\(сведения.st_mtimespec.tv_nsec):\(сведения.st_ctimespec.tv_sec):\(сведения.st_ctimespec.tv_nsec)"
        }
        func совпадения(_ адрес: URL, _ имя: String) throws -> [String] {
            try autoreleasepool {
                let путь = Data(адрес.path.utf8), сейчас = try отпечаток(адрес)
                if let запись = каталоги[путь] {
                    try требовать(запись.отпечаток == сейчас, "Дрейф каталога внутри читающего прохода")
                    return запись.группы[ключ(имя)] ?? []
                }
                var группы: [String: [String]] = [:]
                for имя in try файловаяСистема.contentsOfDirectory(atPath: адрес.path) {
                    let собственное = String(decoding: Array(имя.utf8), as: UTF8.self)
                    группы[ключ(собственное), default: []].append(собственное)
                }
                try требовать(try отпечаток(адрес) == сейчас, "Дрейф каталога при перечислении")
                каталоги[путь] = .init(отпечаток: сейчас, группы: группы)
                return группы[ключ(имя)] ?? []
            }
        }
    }
    private static func требовать(_ условие: Bool, _ причина: String) throws {
        guard условие else { throw ОшибкаПутей.отказ(причина) }
    }
    static func гит(_ корень: URL, _ аргументы: [String], коды: Set<Int32> = [0]) throws -> Data {
        // Канонические literal pathspec и независимость от унаследованного GIT_*.
        try ЧитательПутей.гит(корень, ["--no-replace-objects", "--literal-pathspecs"] + аргументы, коды: коды).0
    }
    private static func строка(_ данные: Data) throws -> String {
        guard let значение = String(data: данные, encoding: .utf8) else { throw ОшибкаПутей.отказ("НеUTF8 Git-путь") }
        return значение.trimmingCharacters(in: .newlines)
    }
    private static func ключ(_ путь: String) -> String {
        путь.precomposedStringWithCanonicalMapping.folding(options: [.caseInsensitive], locale: Locale(identifier: "en_US_POSIX"))
    }
    static func исключён(_ путь: String) -> Bool {
        let части = ИменаПутей.компоненты(путь)
        if части.first == "Proyekcii" { return true }
        let каталоги = части.dropLast().map { $0.lowercased() }
        let служебные: Set<String> = [".git", ".build", ".swiftpm", ".cache", "cache", "caches", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"]
        return каталоги.contains { служебные.contains($0) || $0.hasSuffix("-cache") || $0.hasSuffix("_cache") || $0.hasSuffix(".cache") }
            || (части.count > 2 && части[0].lowercased() == ".obsidian" && ["plugins", "themes"].contains(части[1].lowercased()))
    }
    // Каждое существующее имя сверяется по UTF8, даже на case-insensitive APFS.
    private static func точныйПуть(_ корень: URL, _ путь: String, отсутствуетПоследний: Bool = false,
        контекст: КонтекстЧтения = .init()) throws -> URL {
        try ИменаПутей.проверитьПуть(путь)
        try требовать(!исключён(путь) && !путь.hasPrefix("~") && !путь.hasPrefix("$"), "Исключённый или неоднозначный путь")
        var текущий = корень
        let части = ИменаПутей.компоненты(путь)
        for (номер, часть) in части.enumerated() {
            let совпавшие = try контекст.совпадения(текущий, часть)
            let последний = номер == части.count - 1
            if последний && отсутствуетПоследний {
                try требовать(совпавшие.isEmpty, "Назначение занято или имеет case/NFC-алиас")
                return текущий.appendingPathComponent(часть)
            }
            try требовать(совпавшие.count == 1 && Data(совпавшие[0].utf8) == Data(часть.utf8), "Не точный регистр/NFC пути или отсутствующий родитель: \(путь)")
            текущий.appendPathComponent(часть)
            let состояние = try СостояниеФайлаПереименования(текущий)
            try требовать(!состояние.ссылка && (последний || состояние.каталог), "Символический или не каталожный компонент")
        }
        return текущий
    }
    private static func список(_ корень: URL, _ аргументы: [String]) throws -> [String] {
        try гит(корень, аргументы).split(separator: 0).map {
            guard let путь = String(data: Data($0), encoding: .utf8) else { throw ОшибкаПутей.отказ("НеUTF8 инвентарь") }
            try ИменаПутей.проверитьПуть(путь)
            return путь
        }
    }
    private static func инвентарь(_ корень: URL, контекст: КонтекстЧтения = .init(),
        наблюдение: НаблюдениеОднофайловогоПлана? = nil) throws -> (документы: [String], пути: [String], алиасы: [String: String]) {
        наблюдение?.учесть(.полныеИнвентари)
        try наблюдение?.проверить()
        let отслеживаемые = try список(корень, ["ls-files", "--cached", "-z"])
        let новые = try список(корень, ["ls-files", "--others", "--exclude-standard", "-z"])
        let все = Dictionary((отслеживаемые + новые).map { (Data($0.utf8), $0) }, uniquingKeysWith: { а, _ in а }).values.sorted(by: порядокПутей)
        try требовать(все.count <= 200_000, "Превышен предел конечного инвентаря")
        var документы: [String] = [], пути: [Data: String] = [:], алиасы: [String: String] = [:]
        for путь in все where !исключён(путь) {
            try autoreleasepool {
            let адрес = корень.appendingPathComponent(путь)
            guard let состояние = try? СостояниеФайлаПереименования(адрес) else {
                if путь.hasSuffix(".md") { try требовать(!(try гит(корень, ["status", "--porcelain=v1", "--", путь])).isEmpty, "Исчезнувший Markdown без видимого удаления") }
                return
            }
            пути[Data(путь.utf8)] = путь
            var родитель = путь as NSString
            while родитель.deletingLastPathComponent != "" {
                let имя = родитель.deletingLastPathComponent
                пути[Data(имя.utf8)] = имя; родитель = имя as NSString
            }
            if состояние.ссылка {
                let цель = адрес.resolvingSymlinksInPath().path, префикс = корень.path + "/"
                алиасы[путь] = цель.hasPrefix(префикс) ? String(цель.dropFirst(префикс.count)) : цель
            }
            if путь.hasSuffix(".md") {
                _ = try точныйПуть(корень, путь, контекст: контекст)
                if состояние.обычный { документы.append(путь) }
            }
            }
        }
        return (документы.sorted(by: порядокПутей), Array(пути.values), алиасы)
    }
    private static func прочитатьОбычный(_ адрес: URL, предел: Int) throws -> Data {
        var прежде = stat()
        try требовать(предел >= 0 && lstat(адрес.path, &прежде) == 0 && прежде.st_mode & S_IFMT == S_IFREG, "Не обычный файл для ограниченного чтения")
        // Размер проверяется ДО open/read, включая оставшийся общий бюджет.
        try требовать(прежде.st_size >= 0 && прежде.st_size <= предел, "Превышен предел чтения до загрузки байтов")
        let дескриптор = open(адрес.path, O_RDONLY | O_NOFOLLOW | O_CLOEXEC)
        try требовать(дескриптор >= 0, "Не открыт обычный файл без следования ссылке")
        defer { close(дескриптор) }
        var внутри = stat()
        try требовать(fstat(дескриптор, &внутри) == 0 && внутри.st_mode == прежде.st_mode && внутри.st_dev == прежде.st_dev && внутри.st_ino == прежде.st_ino && внутри.st_size == прежде.st_size, "Дрейф узла до чтения")
        var итог = Data(), буфер = [UInt8](repeating: 0, count: min(65_536, max(1, предел + 1)))
        while true {
            let запрос = min(буфер.count, предел - итог.count + 1)
            let число = буфер.withUnsafeMutableBytes { Darwin.read(дескриптор, $0.baseAddress, запрос) }
            if число < 0 && errno == EINTR { continue }
            try требовать(число >= 0, "Неполное ограниченное чтение")
            if число == 0 { break }
            try требовать(число <= предел - итог.count, "Рост файла за предел при чтении")
            итог.append(contentsOf: буфер.prefix(число))
        }
        var после = stat()
        try требовать(fstat(дескриптор, &после) == 0 && после.st_mode == внутри.st_mode && после.st_size == внутри.st_size
            && после.st_mtimespec.tv_sec == внутри.st_mtimespec.tv_sec && после.st_mtimespec.tv_nsec == внутри.st_mtimespec.tv_nsec
            && после.st_ctimespec.tv_sec == внутри.st_ctimespec.tv_sec && после.st_ctimespec.tv_nsec == внутри.st_ctimespec.tv_nsec,
            "Дрейф узла во время чтения")
        return итог
    }
    private static func снимок(_ корень: URL, _ путь: String, предел: Int = 8_388_608,
        контекст: КонтекстЧтения = .init(), наблюдение: НаблюдениеОднофайловогоПлана? = nil) throws -> ФайлПланаПереименования {
        try autoreleasepool {
        let адрес = try точныйПуть(корень, путь, контекст: контекст), состояние = try СостояниеФайлаПереименования(адрес)
        try требовать(состояние.обычный, "Источник/Markdown должен быть обычным файлом")
        let байты = try прочитатьОбычный(адрес, предел: предел)
        наблюдение?.учесть(.файлыПрочитаны)
        наблюдение?.учесть(.байтыПрочитаны, байты.count)
        try наблюдение?.проверить()
        try требовать(try СостояниеФайлаПереименования(адрес) == состояние, "Дрейф чтения файла")
        return .init(путь: путь, байты: байты, состояние: состояние)
        }
    }
    private static func каталоги(_ корень: URL, _ назначение: String, контекст: КонтекстЧтения = .init()) throws -> [String: СостояниеФайлаПереименования] {
        var итог = ["": try СостояниеФайлаПереименования(корень)], части: [String] = []
        for часть in ИменаПутей.компоненты(назначение).dropLast() {
            части.append(часть); let путь = части.joined(separator: "/")
            итог[путь] = try СостояниеФайлаПереименования(точныйПуть(корень, путь, контекст: контекст))
            try требовать(итог[путь]?.каталог == true, "Не каталожный родитель назначения")
        }
        return итог
    }
    private static func проверитьПрефиксыЦелей(_ корень: URL, _ цели: [String]) throws {
        // Metadata только адресов, уже извлечённых тем же pure-лексером.
        // Gitignore не доказывает отсутствия физического symlink-компонента.
        for путь in цели where !путь.isEmpty {
            try ИменаПутей.проверитьПуть(путь)
            var адрес = корень
            for часть in ИменаПутей.компоненты(путь) {
                адрес.appendPathComponent(часть)
                var сведения = stat()
                if lstat(адрес.path, &сведения) != 0 {
                    try требовать(errno == ENOENT || errno == ENOTDIR, "Не проверен префикс локальной цели")
                    break // Доказанное отсутствие, но не пропуск неизвестного alias.
                }
                try требовать(сведения.st_mode & S_IFMT != S_IFLNK, "Символический компонент цели: \(путь)")
                if сведения.st_mode & S_IFMT != S_IFDIR { break }
            }
        }
    }
    static func построить(корень: URL, исходный: String, целевой: String,
        пределФайла: Int = 8_388_608, пределВсехБайтов: Int = 268_435_456,
        времяСвежести: String? = nil, наблюдение: НаблюдениеОднофайловогоПлана? = nil) throws -> ПланПереименованияФайла {
        try наблюдение?.этап(.вход)
        try требовать((0...8_388_608).contains(пределФайла) && (0...268_435_456).contains(пределВсехБайтов), "Недопустимые конечные бюджеты")
        if let времяСвежести {
            let формат = DateFormatter()
            формат.locale = Locale(identifier: "en_US_POSIX")
            guard let мск = TimeZone(identifier: "Europe/Moscow") else { throw ОшибкаПутей.отказ("Неизвестен часовой пояс MSK") }
            формат.timeZone = мск
            формат.dateFormat = "yyyy-MM-dd HH:mm:ss 'MSK'"
            формат.isLenient = false
            try требовать(времяСвежести.utf8.count == 23
                && времяСвежести.range(of: #"^[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2} MSK$"#, options: .regularExpression) != nil
                && формат.date(from: времяСвежести).map { формат.string(from: $0) == времяСвежести } == true,
                "Неверное время свежести MSK")
        }
        let контекст = КонтекстЧтения()
        try требовать(Data(корень.path.utf8) == Data(корень.standardizedFileURL.resolvingSymlinksInPath().path.utf8), "Нужен физический корень Git-worktree")
        let обнаруженный = URL(fileURLWithPath: try строка(гит(корень, ["rev-parse", "--show-toplevel"]))).resolvingSymlinksInPath().standardizedFileURL
        try требовать(Data(обнаруженный.path.utf8) == Data(корень.path.utf8), "Не корень Git-worktree")
        try требовать(ключ(исходный) != ключ(целевой), "Совпадение или case/NFC-only перенос")
        for путь in [исходный, целевой] {
            try ИменаПутей.проверитьПуть(путь)
            try требовать(!ИменаПутей.имеетПрефикс(путь, "Источники/") && (путь as NSString).deletingLastPathComponent != "Планирование/карточки-шагов", "Защищённый или доменный перенос")
        }
        try наблюдение?.этап(.источник, путь: исходный)
        let источник = try снимок(корень, исходный, предел: min(пределФайла, пределВсехБайтов), контекст: контекст, наблюдение: наблюдение)
        _ = try точныйПуть(корень, целевой, отсутствуетПоследний: true, контекст: контекст)
        let отслеживаемые = try список(корень, ["ls-files", "--cached", "--error-unmatch", "-z", "--", исходный])
        try требовать(отслеживаемые.count == 1 && Data(отслеживаемые[0].utf8) == Data(исходный.utf8), "Источник не единственный tracked-файл")
        try требовать(try гит(корень, ["status", "--porcelain=v1", "-z", "--untracked-files=no", "--", исходный]).isEmpty, "Источник грязный в индексе или рабочем дереве")
        let каталог = try каталоги(корень, целевой, контекст: контекст)
        try наблюдение?.этап(.инвентарь)
        let состав = try инвентарь(корень, контекст: контекст, наблюдение: наблюдение)
        let ключНазначения = ключ(целевой)
        for путь in try список(корень, ["ls-files", "--cached", "-z"]) {
            try autoreleasepool { try требовать(ключ(путь) != ключНазначения, "Назначение занято в Git-индексе") }
        }
        var файлы = [источник], остатокБайтов = пределВсехБайтов - источник.байты.count
        if let наблюдение {
            let первый = состав.документы.firstIndex { Data($0.utf8) != Data(исходный.utf8) }
            try наблюдение.этап(.чтение, путь: первый.map { состав.документы[$0] },
                номер: первый.map { $0 + 1 } ?? 0, всего: состав.документы.count)
        }
        for (номер, путь) in состав.документы.enumerated() where Data(путь.utf8) != Data(исходный.utf8) {
            наблюдение?.установитьДокумент(номер: номер + 1, всего: состав.документы.count, путь: путь)
            try наблюдение?.проверить()
            let файл = try снимок(корень, путь, предел: min(пределФайла, остатокБайтов), контекст: контекст, наблюдение: наблюдение)
            файлы.append(файл); остатокБайтов -= файл.байты.count
        }
        let разбор = try СсылкиОдногоФайла.переписать(
            документы: файлы.filter { $0.путь.hasSuffix(".md") }.map { .init(путь: $0.путь, байты: $0.байты, sha256: хэшПутей($0.байты)) },
            исходный: исходный, целевой: целевой, пути: состав.пути, алиасы: состав.алиасы,
            пределФайла: пределФайла, пределБайтов: пределВсехБайтов - (исходный.hasSuffix(".md") ? 0 : источник.байты.count),
            наблюдение: наблюдение)
        try наблюдение?.этап(.префиксы)
        try проверитьПрефиксыЦелей(корень, разбор.локальныеЦели)
        var правки = разбор.правки
        try наблюдение?.этап(.свежесть)
        for номер in правки.indices where правки[номер].итоговый.hasSuffix(".md") {
            let правка = правки[номер]
            guard let текст = String(data: правка.байты, encoding: .utf8) else { throw ОшибкаПутей.отказ("Не UTF-8 для свежести") }
            let естьМаркеры = текст.contains("FUM-MD-RECENCY:BEGIN") || текст.contains("FUM-MD-RECENCY:END")
            guard let времяСвежести else {
                try требовать(!естьМаркеры, "Нужно явное время свежести при существующих метках")
                continue
            }
            if естьМаркеры {
                let шаблон = #"(?:\A|\r?\n)<!-- FUM-MD-RECENCY:BEGIN -->\r?\n<!-- last-content-edit: ([^>]+) -->\r?\n<!-- content-sha256: sha256:([0-9a-f]{64}) -->\r?\n<!-- FUM-MD-RECENCY:END -->\r?\n?\z"#
                let выражение = try NSRegularExpression(pattern: шаблон)
                try требовать(текст.components(separatedBy: "FUM-MD-RECENCY:BEGIN").count == 2
                    && текст.components(separatedBy: "FUM-MD-RECENCY:END").count == 2
                    && выражение.firstMatch(in: текст, range: NSRange(текст.startIndex..., in: текст)) != nil,
                    "Повреждённая структура свежести")
            }
            let естьВозвратКаретки = правка.байты.contains(13)
            if естьВозвратКаретки {
                let знаки = Array(правка.байты)
                var курсор = 0
                while курсор < знаки.count {
                    if знаки[курсор] == 13 {
                        try требовать(курсор + 1 < знаки.count && знаки[курсор + 1] == 10, "Смешанные переводы строк свежести")
                        курсор += 2
                    } else {
                        try требовать(знаки[курсор] != 10, "Смешанные переводы строк свежести")
                        курсор += 1
                    }
                }
            }
            // Общий обновитель получает LF; обратное преобразование проверяется
            // побайтно и сохраняет исходное тело uniform CRLF вне href/footer.
            let дляОбновителя = естьВозвратКаретки ? Data(текст.replacingOccurrences(of: "\r\n", with: "\n").utf8) : правка.байты
            if естьВозвратКаретки {
                let обратно = String(decoding: дляОбновителя, as: UTF8.self).replacingOccurrences(of: "\n", with: "\r\n")
                try требовать(Data(обратно.utf8) == правка.байты, "Необратимая нормализация CRLF свежести")
            }
            var обновлённые = try РешательСсылокПакета.обновитьСвежесть(дляОбновителя, путь: правка.итоговый, время: времяСвежести)
            if естьВозвратКаретки {
                let единые = String(decoding: обновлённые, as: UTF8.self).replacingOccurrences(of: "\r\n", with: "\n")
                обновлённые = Data(единые.replacingOccurrences(of: "\n", with: "\r\n").utf8)
            }
            правки[номер] = .init(исходный: правка.исходный, итоговый: правка.итоговый,
                байты: обновлённые, числоСсылок: правка.числоСсылок)
        }
        try требовать(правки.allSatisfy { $0.байты.count <= пределФайла }, "Превышен бюджет итоговой правки")
        let размерыДо = Dictionary(uniqueKeysWithValues: файлы.map { (Data($0.путь.utf8), $0.байты.count) })
        let итогВсехБайтов = файлы.reduce(0) { $0 + $1.байты.count }
            + правки.reduce(0) { $0 + $1.байты.count - (размерыДо[Data($1.исходный.utf8)] ?? 0) }
        try требовать(итогВсехБайтов <= пределВсехБайтов, "Превышен общий бюджет итоговой свежести")
        let адресИндекса = URL(fileURLWithPath: try строка(гит(корень, ["rev-parse", "--path-format=absolute", "--git-path", "index"])))
        let индексСостояние = try СостояниеФайлаПереименования(адресИндекса)
        try требовать(индексСостояние.обычный, "Индекс не обычный файл")
        let план = ПланПереименованияФайла(корень: корень, исходный: исходный, целевой: целевой,
            файлы: файлы.sorted { порядокПутей($0.путь, $1.путь) }, правки: правки, каталоги: каталог, документы: состав.документы, локальныеЦели: разбор.локальныеЦели,
            голова: try гит(корень, ["rev-parse", "--verify", "HEAD"]), ветка: try гит(корень, ["symbolic-ref", "-q", "HEAD"], коды: [0, 1]),
            статус: try гит(корень, ["status", "--porcelain=v1", "-z", "--untracked-files=all"]),
            адресИндекса: адресИндекса, индекс: try прочитатьОбычный(адресИндекса, предел: 33_554_432),
            записиИндекса: try гит(корень, ["ls-files", "--stage", "-z"]), режимИндекса: индексСостояние.режим & 0o7777,
            времяСвежести: времяСвежести)
        try наблюдение?.этап(.сверка, путь: план.файлы.first?.путь, номер: 1, всего: план.файлы.count)
        try сверить(план, наблюдение: наблюдение)
        try наблюдение?.этап(.готово)
        return план
    }
    static func сверить(_ план: ПланПереименованияФайла, статус: Bool = true,
        наблюдение: НаблюдениеОднофайловогоПлана? = nil) throws {
        let контекст = КонтекстЧтения()
        _ = try точныйПуть(план.корень, план.целевой, отсутствуетПоследний: true, контекст: контекст)
        try требовать(try каталоги(план.корень, план.целевой, контекст: контекст) == план.каталоги, "Дрейф identity родителя назначения")
        for (номер, файл) in план.файлы.enumerated() {
            do {
                наблюдение?.установитьДокумент(номер: номер + 1, всего: план.файлы.count,
                    путь: файл.путь, хэш: хэшПутей(файл.байты), байты: файл.байты.count)
                try наблюдение?.проверить()
                let текущий = try снимок(план.корень, файл.путь, предел: файл.байты.count, контекст: контекст, наблюдение: наблюдение)
                try требовать(текущий.байты == файл.байты && текущий.состояние == файл.состояние, "Не совпали байты/узел")
            } catch {
                try наблюдение?.проверить()
                throw ОшибкаПутей.отказ("Дрейф файла перед переносом: \(error)")
            }
        }
        try сверитьГит(план)
        try проверитьПрефиксыЦелей(план.корень, план.локальныеЦели)
        try требовать(try инвентарь(план.корень, контекст: контекст, наблюдение: наблюдение).документы == план.документы, "Дрейф Markdown-инвентаря")
        if статус { try требовать(try гит(план.корень, ["status", "--porcelain=v1", "-z", "--untracked-files=all"]) == план.статус, "Дрейф Git-status") }
    }
    private static func сверитьГит(_ план: ПланПереименованияФайла) throws {
        try требовать(try гит(план.корень, ["rev-parse", "--verify", "HEAD"]) == план.голова, "Дрейф HEAD")
        try требовать(try гит(план.корень, ["symbolic-ref", "-q", "HEAD"], коды: [0, 1]) == план.ветка, "Дрейф ref")
        let состояние = try СостояниеФайлаПереименования(план.адресИндекса)
        try требовать(состояние.обычный && состояние.режим & 0o7777 == план.режимИндекса, "Дрейф типа или режима индекса")
        try требовать(try прочитатьОбычный(план.адресИндекса, предел: 33_554_432) == план.индекс, "Дрейф точных байтов индекса")
    }
    private static func копия(_ каталог: URL, _ байты: Data, _ режим: mode_t, _ вид: String) throws -> URL {
        let адрес = каталог.appendingPathComponent(".fum-rename-\(вид)-\(UUID().uuidString.lowercased())")
        let дескриптор = open(адрес.path, O_CREAT | O_EXCL | O_NOFOLLOW | O_WRONLY, режим)
        try требовать(дескриптор >= 0, "Не создана временная копия")
        defer { close(дескриптор) }
        do {
            try требовать(fchmod(дескриптор, режим) == 0, "Не установлен режим копии")
            try байты.withUnsafeBytes { буфер in
                var смещение = 0
                while смещение < буфер.count {
                    let число = Darwin.write(дескриптор, буфер.baseAddress!.advanced(by: смещение), буфер.count - смещение)
                    if число < 0 && errno == EINTR { continue }
                    try требовать(число > 0, "Неполная запись временной копии"); смещение += число
                }
            }
            try требовать(fsync(дескриптор) == 0, "Не синхронизирована временная копия")
        } catch { try? файловаяСистема.removeItem(at: адрес); throw error }
        return адрес
    }
    private struct ПодготовленнаяПравка {
        let правка: ПравкаФайлаПереименования
        let новая: URL
        let резервная: URL
    }
    private static func сверитьПрименение(_ план: ПланПереименованияФайла) throws {
        let контекст = КонтекстЧтения()
        try проверитьПрефиксыЦелей(план.корень, план.локальныеЦели.map { Data($0.utf8) == Data(план.исходный.utf8) ? план.целевой : $0 })
        let состояниеИндекса = try СостояниеФайлаПереименования(план.адресИндекса)
        try требовать(состояниеИндекса.обычный && состояниеИндекса.режим & 0o7777 == план.режимИндекса, "Дрейф типа или режима индекса после переноса")
        try требовать(try гит(план.корень, ["rev-parse", "--verify", "HEAD"]) == план.голова, "Дрейф HEAD после переноса")
        try требовать(try гит(план.корень, ["symbolic-ref", "-q", "HEAD"], коды: [0, 1]) == план.ветка, "Дрейф ref после переноса")
        var записи: [(Data, Data)] = []
        for запись in план.записиИндекса.split(separator: 0) {
            guard let граница = запись.firstIndex(of: 9) else { throw ОшибкаПутей.отказ("Повреждённая stage-запись") }
            let начало = запись.index(after: граница), путь = Data(запись[начало...])
            let новый = путь == Data(план.исходный.utf8) ? Data(план.целевой.utf8) : путь
            записи.append((новый, Data(запись[..<начало]) + новый + Data([0])))
        }
        let ожидание = записи.sorted { $0.0.lexicographicallyPrecedes($1.0) }.reduce(into: Data()) { $0.append($1.1) }
        try требовать(try гит(план.корень, ["ls-files", "--stage", "-z"]) == ожидание, "Неожиданная дельта Git-индекса после переноса")
        for файл in план.файлы {
            let путь = Data(файл.путь.utf8) == Data(план.исходный.utf8) ? план.целевой : файл.путь
            let текущий = try снимок(план.корень, путь, контекст: контекст)
            let правка = план.правки.first { Data($0.исходный.utf8) == Data(файл.путь.utf8) }
            try требовать(текущий.байты == (правка?.байты ?? файл.байты) && текущий.состояние.режим == файл.состояние.режим,
                "Не совпали итоговые байты или режим")
        }
        let ожиданиеДокументов = (план.документы.filter { Data($0.utf8) != Data(план.исходный.utf8) } + (план.целевой.hasSuffix(".md") ? [план.целевой] : [])).sorted(by: порядокПутей)
        try требовать(try инвентарь(план.корень, контекст: контекст).документы == ожиданиеДокументов, "Не совпал итоговый Markdown-инвентарь")
        try требовать((try? СостояниеФайлаПереименования(план.корень.appendingPathComponent(план.исходный))) == nil, "Остался прежний путь после переноса")
    }
    static func применить(_ план: ПланПереименованияФайла,
        передУстановкой: ((Int) throws -> Void)? = nil,
        передВосстановлением: ((Int) throws -> Void)? = nil,
        переносДляПроверки: (() throws -> Void)? = nil) throws {
        try сверить(план)
        var подготовленные: [ПодготовленнаяПравка] = [], установленные: [ПодготовленнаяПравка] = []
        var попыткаПереноса = false, перенесён = false, сохранить: Set<URL> = []
        let резервИндекса = try копия(план.корень, план.индекс, план.режимИндекса, "index")
        var намерение: URL?
        func очистить() -> [String] {
            var ошибки: [String] = []
            for адрес in подготовленные.flatMap({ [$0.новая, $0.резервная] }) + [резервИндекса] + (намерение.map { [$0] } ?? []) where !сохранить.contains(адрес) {
                if файловаяСистема.fileExists(atPath: адрес.path) {
                    do { try файловаяСистема.removeItem(at: адрес) } catch { ошибки.append("Очистка \(адрес.path): \(error)") }
                }
            }
            return ошибки
        }
        func статусБезСобственныхКопий() throws -> Data {
            let адреса = подготовленные.flatMap { [$0.новая, $0.резервная] } + [резервИндекса] + (намерение.map { [$0] } ?? [])
            let пути = Set(адреса.map { Data($0.path.dropFirst(план.корень.path.count + 1).utf8) })
            let статус = try гит(план.корень, ["status", "--porcelain=v1", "-z", "--untracked-files=all"])
            return статус.split(separator: 0).reduce(into: Data()) { итог, запись in
                if запись.starts(with: [63, 63, 32]) && пути.contains(Data(запись.dropFirst(3))) { return }
                итог.append(contentsOf: запись); итог.append(0)
            }
        }
        do {
            let запись: [String: Any] = ["схема": "fum.намерение-переименования-файла.1", "исходный": план.исходный, "целевой": план.целевой,
                "индекс_sha256": хэшПутей(план.индекс), "голова_sha256": хэшПутей(план.голова),
                "исход": "перед эффектом; завершение ещё не подтверждено", "полномочия": false]
            намерение = try копия(план.корень, JSONSerialization.data(withJSONObject: запись, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) + Data([10]), 0o600, "intent")
            for правка in план.правки {
                guard let файл = план.файлы.first(where: { Data($0.путь.utf8) == Data(правка.исходный.utf8) }) else { throw ОшибкаПутей.отказ("Нет исходного снимка правки") }
                let каталог = план.корень.appendingPathComponent(правка.итоговый).deletingLastPathComponent()
                let новая = try копия(каталог, правка.байты, файл.состояние.режим & 0o7777, "new")
                do {
                    let резервная = try копия(каталог, файл.байты, файл.состояние.режим & 0o7777, "backup")
                    подготовленные.append(.init(правка: правка, новая: новая, резервная: резервная))
                } catch { try? файловаяСистема.removeItem(at: новая); throw error }
            }
            try сверить(план, статус: false)
            try требовать(!файловаяСистема.fileExists(atPath: план.адресИндекса.path + ".lock"), "Индекс занят другим писателем")
            // Намерение предшествует эффекту. Тестовый seam моделирует отказ
            // подтверждения ПОСЛЕ настоящего mv либо частичной записи индекса.
            попыткаПереноса = true
            if let переносДляПроверки { try переносДляПроверки() }
            else { _ = try гит(план.корень, ["mv", "--", план.исходный, план.целевой]) }
            перенесён = true
            for (номер, запись) in подготовленные.enumerated() {
                установленные.append(запись)
                try передУстановкой?(номер + 1)
                try требовать(rename(запись.новая.path, план.корень.appendingPathComponent(запись.правка.итоговый).path) == 0, "Не установлена правка")
            }
            try сверитьПрименение(план)
        } catch {
            var ошибки: [String] = []
            if попыткаПереноса && !перенесён {
                let прежний = try? снимок(план.корень, план.исходный)
                let ожидаемый = план.файлы.first { Data($0.путь.utf8) == Data(план.исходный.utf8) }
                let цель = try? СостояниеФайлаПереименования(план.корень.appendingPathComponent(план.целевой))
                let индекс = try? прочитатьОбычный(план.адресИндекса, предел: 33_554_432)
                let нулевойЭффект = прежний?.байты == ожидаемый?.байты && прежний?.состояние == ожидаемый?.состояние && цель == nil && индекс == план.индекс
                if !нулевойЭффект {
                    сохранить.formUnion(подготовленные.map(\.резервная) + [резервИндекса] + (намерение.map { [$0] } ?? []))
                    let очистка = очистить()
                    throw ОшибкаПутей.отказ("UNKNOWN: неподтверждённый эффект git mv; повтор/откат не выполнен. Резерв индекса сохранён: \(резервИндекса.path); источник_есть=\(прежний != nil), назначение_есть=\(цель != nil), индекс_совпал=\(индекс == план.индекс); \(error); \(очистка.joined(separator: "; "))")
                }
            }
            for (номер, запись) in установленные.reversed().enumerated() {
                do {
                    try передВосстановлением?(номер + 1)
                    let адрес = план.корень.appendingPathComponent(запись.правка.итоговый)
                    let режим = try СостояниеФайлаПереименования(запись.резервная).режим & 0o7777
                    let копияВосстановления = try копия(адрес.deletingLastPathComponent(), прочитатьОбычный(запись.резервная, предел: 8_388_608), режим, "restore")
                    defer { try? файловаяСистема.removeItem(at: копияВосстановления) }
                    try требовать(rename(копияВосстановления.path, адрес.path) == 0, "Не восстановлена копия")
                } catch { сохранить.insert(запись.резервная); ошибки.append("Резервная копия сохранена: \(запись.резервная.path); \(error)") }
            }
            if перенесён {
                do {
                    _ = try гит(план.корень, ["mv", "--", план.целевой, план.исходный])
                    let заменаИндекса = try копия(план.адресИндекса.deletingLastPathComponent(), план.индекс, план.режимИндекса, "index-restore")
                    defer { try? файловаяСистема.removeItem(at: заменаИндекса) }
                    try требовать(rename(заменаИндекса.path, план.адресИндекса.path) == 0, "Не восстановлены байты индекса")
                } catch { сохранить.insert(резервИндекса); ошибки.append("Откат Git/index: \(error); резерв \(резервИндекса.path)") }
            }
            if ошибки.isEmpty {
                do {
                    let контекстОтката = КонтекстЧтения()
                    try сверитьГит(план)
                    try проверитьПрефиксыЦелей(план.корень, план.локальныеЦели)
                    for файл in план.файлы {
                        let текущий = try снимок(план.корень, файл.путь, контекст: контекстОтката)
                        try требовать(текущий.байты == файл.байты && текущий.состояние.режим == файл.состояние.режим, "Откат не восстановил байты/режим")
                    }
                    try требовать(try инвентарь(план.корень, контекст: контекстОтката).документы == план.документы, "Откат не восстановил Markdown-инвентарь")
                    try требовать(try статусБезСобственныхКопий() == план.статус, "Откат не восстановил status")

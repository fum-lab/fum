import АктуализацияПутей
import CryptoKit
import Darwin
import Foundation
import КонтейнерНаблюдений

/// Сохраняет каждое неизменяемое намерение контрольной точки в существующем сегменте наблюдений.
public actor ХранилищеКонтрольныхТочекВСегменте {
    private struct Спецификация: Codable, Equatable {
        let схема: String
        let operationID: String
        let фаза: КонтрольнаяТочкаНормализацииКорнейАгентов.ФазаНамерения
        let sha256: String
    }

    private static let схема = "fum.контрольная-точка-нормализации-в-сегменте.1"
    private static let тип = "fum.контрольная-точка-нормализации-корней-агентов"
    private static let источник = "ПрименениеНормализацииКорнейАгентов"

    private let кореньДанных: URL

    public init(кореньДанных: URL) {
        self.кореньДанных = кореньДанных.standardizedFileURL
    }

    public func загрузитьПоследнююКонтрольнуюТочку(
        operationID: String
    ) throws -> КонтрольнаяТочкаНормализацииКорнейАгентов? {
        let сегмент: Сегмент
        do {
            сегмент = try Сегмент(кореньДанных: кореньДанных, запись: false, создать: false)
        } catch ОшибкаКонтейнера.система(let код) where код == ENOENT {
            return nil
        }
        defer { сегмент.закрыть() }
        guard !сегмент.естьХвост else { throw ОшибкаАдаптераКонтрольнойТочки.неполныйХвост }

        var последняя: КонтрольнаяТочкаНормализацииКорнейАгентов?
        for квитанция in сегмент.записи where квитанция.описание.тип == Self.тип {
            let спецификация = try Self.проверитьСпецификацию(квитанция.описание)
            guard спецификация.operationID == operationID else { continue }
            последняя = try прочитать(квитанция: квитанция, спецификация: спецификация, из: сегмент)
        }
        return последняя
    }

    public func сохранитьИПеречитать(
        _ намерение: КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение
    ) throws -> КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение {
        guard Self.хэш(намерение.каноническиеБайты) == намерение.sha256 else {
            throw ОшибкаАдаптераКонтрольнойТочки.неверныйХэш
        }
        let спецификация = Спецификация(
            схема: Self.схема,
            operationID: намерение.operationID,
            фаза: намерение.фаза,
            sha256: намерение.sha256)
        let байтыСпецификации = try Self.закодировать(спецификация)
        let идентификатор = Self.идентификатор(спецификация)
        let писатель = try Сегмент(кореньДанных: кореньДанных, запись: true, создать: true)
        defer { писатель.закрыть() }
        guard !писатель.естьХвост else { throw ОшибкаАдаптераКонтрольнойТочки.неполныйХвост }

        let прежняя = писатель.записи.first { $0.описание.идентификатор == идентификатор }
        let описание: ОписаниеНаблюдения
        if let прежняя {
            let сохранённаяСпецификация = try Self.проверитьСпецификацию(прежняя.описание)
            guard сохранённаяСпецификация == спецификация,
                  прежняя.описание.спецификация == байтыСпецификации,
                  прежняя.хэш == намерение.sha256,
                  прежняя.размер == UInt64(намерение.каноническиеБайты.count) else {
                throw ОшибкаАдаптераКонтрольнойТочки.конфликтИдентификатора
            }
            описание = прежняя.описание
        } else {
            описание = ОписаниеНаблюдения(
                идентификатор: идентификатор,
                тип: Self.тип,
                версияСхемы: 1,
                источник: Self.источник,
                время: Self.текущееВремя(),
                спецификация: байтыСпецификации)
        }

        let сохранённаяКвитанция = try писатель.добавить(описание, данные: намерение.каноническиеБайты)
        guard сохранённаяКвитанция.описание == описание,
              сохранённаяКвитанция.хэш == намерение.sha256,
              сохранённаяКвитанция.размер == UInt64(намерение.каноническиеБайты.count) else {
            throw ОшибкаАдаптераКонтрольнойТочки.невернаяКвитанция
        }
        писатель.закрыть()

        let читатель = try Сегмент(кореньДанных: кореньДанных, запись: false, создать: false)
        defer { читатель.закрыть() }
        guard !читатель.естьХвост else { throw ОшибкаАдаптераКонтрольнойТочки.неполныйХвост }
        let перечитаннаяКвитанция = try читатель.квитанция(идентификатор)
        let перечитанныеБайты = try читатель.извлечь(идентификатор)
        let перечитаннаяСпецификация = try Self.проверитьСпецификацию(перечитаннаяКвитанция.описание)
        let контрольнаяТочка = try Self.декодироватьТочку(
            перечитанныеБайты,
            спецификация: перечитаннаяСпецификация,
            хэшКвитанции: перечитаннаяКвитанция.хэш)
        let перечитанноеНамерение = КонтрольнаяТочкаНормализацииКорнейАгентов.Намерение(
            operationID: перечитаннаяСпецификация.operationID,
            фаза: перечитаннаяСпецификация.фаза,
            каноническиеБайты: перечитанныеБайты,
            sha256: перечитаннаяСпецификация.sha256)
        guard контрольнаяТочка.operationID == намерение.operationID,
              перечитанноеНамерение == намерение else {
            throw ОшибкаАдаптераКонтрольнойТочки.неверноеПеречитывание
        }
        return перечитанноеНамерение
    }

    private func прочитать(
        квитанция: Квитанция,
        спецификация: Спецификация,
        из сегмент: Сегмент
    ) throws -> КонтрольнаяТочкаНормализацииКорнейАгентов {
        guard квитанция.описание.идентификатор == Self.идентификатор(спецификация) else {
            throw ОшибкаАдаптераКонтрольнойТочки.неверныйИдентификатор
        }
        let байты = try сегмент.извлечь(квитанция.описание.идентификатор)
        return try Self.декодироватьТочку(байты, спецификация: спецификация, хэшКвитанции: квитанция.хэш)
    }

    private static func проверитьСпецификацию(_ описание: ОписаниеНаблюдения) throws -> Спецификация {
        guard описание.тип == тип, описание.версияСхемы == 1, описание.источник == источник else {
            throw ОшибкаАдаптераКонтрольнойТочки.неверноеОписание
        }
        let спецификация: Спецификация
        do {
            спецификация = try JSONDecoder().decode(Спецификация.self, from: описание.спецификация)
        } catch {
            throw ОшибкаАдаптераКонтрольнойТочки.неверноеОписание
        }
        guard спецификация.схема == схема,
              try закодировать(спецификация) == описание.спецификация,
              описание.идентификатор == идентификатор(спецификация) else {
            throw ОшибкаАдаптераКонтрольнойТочки.неверноеОписание
        }
        return спецификация
    }

    private static func декодироватьТочку(
        _ байты: Data,
        спецификация: Спецификация,
        хэшКвитанции: String
    ) throws -> КонтрольнаяТочкаНормализацииКорнейАгентов {
        guard хэш(байты) == спецификация.sha256,
              хэшКвитанции == спецификация.sha256 else {
            throw ОшибкаАдаптераКонтрольнойТочки.неверныйХэш
        }
        let точка: КонтрольнаяТочкаНормализацииКорнейАгентов
        do {
            точка = try НормализацияКорнейАгентов.декодироватьКаноническуюКонтрольнуюТочку(из: байты)
        } catch {
            throw ОшибкаАдаптераКонтрольнойТочки.невернаяТочка
        }
        guard точка.operationID == спецификация.operationID else {
            throw ОшибкаАдаптераКонтрольнойТочки.невернаяТочка
        }
        let ожидаемаяФаза: КонтрольнаяТочкаНормализацииКорнейАгентов.Фаза
        switch спецификация.фаза {
        case .намерение: ожидаемаяФаза = .намерение
        case .подтверждённыйШаг: ожидаемаяФаза = .применение
        case .терминал: ожидаемаяФаза = .завершено
        case .неизвестно: ожидаемаяФаза = .неизвестно
        }
        guard точка.фаза == ожидаемаяФаза else {
            throw ОшибкаАдаптераКонтрольнойТочки.невернаяТочка
        }
        return точка
    }

    private static func идентификатор(_ спецификация: Спецификация) -> String {
        "fum-нормализация-корней-агентов/\(спецификация.operationID)/\(спецификация.фаза.rawValue)/\(спецификация.sha256)"
    }

    private static func закодировать<T: Encodable>(_ значение: T) throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(значение)
    }

    private static func хэш(_ данные: Data) -> String {
        SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
    }

    private static func текущееВремя() -> String {
        let форматтер = ISO8601DateFormatter()
        форматтер.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        return форматтер.string(from: Date())
    }
}

private enum ОшибкаАдаптераКонтрольнойТочки: Error {
    case неполныйХвост
    case неверныйХэш
    case конфликтИдентификатора
    case невернаяКвитанция
    case неверноеПеречитывание
    case неверныйИдентификатор
    case неверноеОписание
    case невернаяТочка
}

import Foundation
import CryptoKit

enum ВидУзлаМиграции: String, Codable, Sendable {
    case файл, каталог, ссылка, внешняяГраница
}

struct УзелОбщейМиграции: Codable, Equatable, Sendable {
    var путь: String
    var вид: ВидУзлаМиграции
    var режим: String
    var объект: String = ""
    var байты: Data = Data()
    var дословный: Bool = false
}

struct КорневоеОтображениеМиграции: Codable, Equatable, Sendable {
    var исходный: String
    var целевой: String
    var источникИмени: String
    var ревизия = "837e2ce107b97ee7b9d3344c9fe99142281fe393"
}

struct ОсноваОбщейМиграции: Codable, Equatable, Sendable {
    var корневаяЗадача: String
    var владелец: String
    var ветка: String
    var коммит: String
    var дерево: String
    var индексSHA256: String
}

struct СтрокаОбщегоОтображения: Codable, Equatable, Sendable {
    var исходный: String
    var целевой: String
}

struct РазрешённыйДокументМиграции: Codable, Equatable, Sendable {
    var байтыПосле: Data
    var целиПосле: [String]
    var полнотаПроверена: Bool
}

struct ДокументПланаОбщейМиграции: Codable, Equatable, Sendable {
    var исходный: String
    var целевой: String
    var исходныйSHA256: String
    var результат: РазрешённыйДокументМиграции
}

enum ВидГруппыМиграции: String, Codable, Sendable {
    case неподвижная, перенос, объединениеКаталогов, дубликат, препятствие
}

struct ГруппаОбщейМиграции: Codable, Equatable, Sendable {
    var целевой: String
    var исходные: [String]
    var вид: ВидГруппыМиграции
}

struct ПрепятствиеОбщейМиграции: Codable, Equatable, Sendable {
    var код: String
    var пути: [String]
}

struct ПланОбщейМиграции: Codable, Equatable, Sendable {
    var схема = "fum.план-общей-миграции-путей.1"
    var основа: ОсноваОбщейМиграции
    var корни: [КорневоеОтображениеМиграции]
    var отображения: [СтрокаОбщегоОтображения]
    var документы: [ДокументПланаОбщейМиграции]
    var группы: [ГруппаОбщейМиграции]
    var препятствия: [ПрепятствиеОбщейМиграции]
    var снимокSHA256: String
    var применениеРазрешено = false
}

enum ОтказОбщейМиграции: Error, Equatable { case условие(String) }

enum ОбщийПланировщикПутей {
    static func построить(основа: ОсноваОбщейМиграции, ожидаемаяОснова: ОсноваОбщейМиграции,
        узлы: [УзелОбщейМиграции], корни: [КорневоеОтображениеМиграции],
        документы: [String: РазрешённыйДокументМиграции] = [:]) throws -> ПланОбщейМиграции {
        let кодировщик = JSONEncoder(); кодировщик.outputFormatting = [.sortedKeys]
        guard try кодировщик.encode(основа) == кодировщик.encode(ожидаемаяОснова), !основа.владелец.isEmpty,
              основа.ветка.hasPrefix("refs/heads/"),
              основа.корневаяЗадача.range(of: #"\A[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\z"#, options: .regularExpression) != nil,
              основа.коммит.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil,
              основа.дерево.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil,
              основа.индексSHA256.range(of: #"\A[0-9a-f]{64}\z"#, options: .regularExpression) != nil else {
            throw ОтказОбщейМиграции.условие("неверное-происхождение")
        }
        var препятствия: [ПрепятствиеОбщейМиграции] = []
        func препятствие(_ код: String, _ пути: [String]) {
            let запись = ПрепятствиеОбщейМиграции(код: код, пути: пути.sorted(by: порядок))
            if !препятствия.contains(запись) { препятствия.append(запись) }
        }
        var записи: [Data: УзелОбщейМиграции] = [:]
        for узел in узлы {
            try проверитьПуть(узел.путь)
            let режимы: [ВидУзлаМиграции: Set<String>] = [.файл: ["100644", "100755"], .каталог: ["040000"], .ссылка: ["120000"], .внешняяГраница: ["160000"]]
            guard режимы[узел.вид]?.contains(узел.режим) == true else { throw ОтказОбщейМиграции.условие("неверный-тип-или-режим") }
            guard записи.updateValue(узел, forKey: Data(узел.путь.utf8)) == nil else { throw ОтказОбщейМиграции.условие("повторный-исходный-путь") }
        }
        let точныеДокументы = Dictionary(uniqueKeysWithValues: документы.map { (Data($0.key.utf8), $0.value) })
        for (путь, проверка) in точныеДокументы {
            guard let узел = записи[путь], узел.вид == .файл, (узел.путь as NSString).pathExtension.lowercased() == "md" else {
                throw ОтказОбщейМиграции.условие("документ-вне-точного-инвентаря")
            }
            for цель in проверка.целиПосле { try проверитьПуть(цель) }
            if узел.дословный, проверка.байтыПосле != узел.байты { препятствие("изменение-дословного-источника", [узел.путь]) }
        }
        for узел in узлы where узел.вид == .файл && (узел.путь as NSString).pathExtension.lowercased() == "md" {
            if !узел.дословный, точныеДокументы[Data(узел.путь.utf8)]?.полнотаПроверена != true {
                препятствие("не-проверены-ссылки", [узел.путь])
            }
        }
        func проверитьАлиасы(_ пути: [String], код: String) {
            var компоненты: [Data: Set<Data>] = [:]
            for путь in пути {
                var префикс = ""
                for часть in ИменаПутей.компоненты(путь) {
                    префикс += (префикс.isEmpty ? "" : "/") + часть
                    компоненты[ключКоллизии(префикс), default: []].insert(Data(префикс.utf8))
                }
            }
            for группа in компоненты.values where группа.count > 1 {
                препятствие(код, группа.map { String(decoding: $0, as: UTF8.self) })
            }
        }
        проверитьАлиасы(узлы.map(\.путь), код: "коллизия-исходных-компонентов")
        for корень in корни {
            try проверитьПуть(корень.исходный); try проверитьПуть(корень.целевой)
            guard !корень.источникИмени.isEmpty, корень.ревизия == "837e2ce107b97ee7b9d3344c9fe99142281fe393" else { throw ОтказОбщейМиграции.условие("не-подтверждено-имя") }
            if ключКоллизии(корень.исходный) == ключКоллизии(корень.целевой), Data(корень.исходный.utf8) != Data(корень.целевой.utf8) {
                препятствие("переименование-только-регистра-или-Unicode", [корень.исходный, корень.целевой])
            }
            if вложен(корень.целевой, в: корень.исходный), Data(корень.исходный.utf8) != Data(корень.целевой.utf8) {
                препятствие("каталог-внутри-себя", [корень.исходный, корень.целевой])
            }
            if записи[Data(корень.исходный.utf8)] == nil, записи[Data(корень.целевой.utf8)] == nil {
                препятствие("нет-источника-и-назначения", [корень.исходный, корень.целевой])
            }
        }
        for левый in корни.indices {
            for правый in корни.indices where правый > левый {
                if вложен(корни[левый].исходный, в: корни[правый].исходный) || вложен(корни[правый].исходный, в: корни[левый].исходный) {
                    throw ОтказОбщейМиграции.условие("пересекающиеся-исходные-корни")
                }
            }
        }
        var отображения: [СтрокаОбщегоОтображения] = [], назначения: [Data: [УзелОбщейМиграции]] = [:]
        let упорядоченные = узлы.sorted { порядок($0.путь, $1.путь) }
        for узел in упорядоченные {
            let выбранные = корни.filter { вложен(узел.путь, в: $0.исходный) }
            var цель = узел.путь
            if let корень = выбранные.first {
                цель = корень.целевой + String(decoding: узел.путь.utf8.dropFirst(корень.исходный.utf8.count), as: UTF8.self)
            }
            try проверитьПуть(цель)
            отображения.append(.init(исходный: узел.путь, целевой: цель))
            назначения[Data(цель.utf8), default: []].append(узел)
        }
        var группы: [ГруппаОбщейМиграции] = []
        var документыПлана: [ДокументПланаОбщейМиграции] = []
        for пара in отображения {
            if let проверка = точныеДокументы[Data(пара.исходный.utf8)], let узел = записи[Data(пара.исходный.utf8)] {
                документыПлана.append(.init(исходный: пара.исходный, целевой: пара.целевой, исходныйSHA256: хэш(узел.байты), результат: проверка))
            }
        }
        for ключ in назначения.keys.sorted(by: { $0.lexicographicallyPrecedes($1) }) {
            let цель = String(decoding: ключ, as: UTF8.self), члены = назначения[ключ]!
            let исходные = члены.map(\.путь).sorted(by: порядок)
            let неподвижная = члены.count == 1 && Data(члены[0].путь.utf8) == ключ
            var вид: ВидГруппыМиграции = неподвижная ? .неподвижная : .перенос
            if !неподвижная, члены.contains(where: { $0.вид == .ссылка || $0.вид == .внешняяГраница }) {
                препятствие("символическая-ссылка-или-чужая-граница", исходные); вид = .препятствие
            } else if члены.allSatisfy({ $0.вид == .каталог }) {
                if члены.count > 1 { вид = .объединениеКаталогов }
            } else if члены.allSatisfy({ $0.вид == .файл }) {
                if члены.count > 1 {
                    if члены.contains(where: { $0.байты != члены[0].байты || $0.режим != члены[0].режим }) {
                        препятствие("разные-листья", исходные); вид = .препятствие
                    } else { вид = .дубликат }
                    let результаты = члены.map { член in
                        точныеДокументы[Data(член.путь.utf8)] ?? .init(байтыПосле: член.байты, целиПосле: [], полнотаПроверена: false)
                    }
                    if let первый = результаты.first,
                       результаты.contains(where: { $0.байтыПосле != первый.байтыПосле || $0.целиПосле.map({ Data($0.utf8) }) != первый.целиПосле.map({ Data($0.utf8) }) }) {
                        препятствие("разная-семантика-ссылок", исходные); вид = .препятствие
                    }
                }
                if !неподвижная, (цель as NSString).pathExtension.lowercased() == "md" {
                    for член in члены {
                        if член.дословный {
                            if let проверка = точныеДокументы[Data(член.путь.utf8)], проверка.байтыПосле != член.байты { препятствие("изменение-дословного-источника", [член.путь]); вид = .препятствие }
                        } else if точныеДокументы[Data(член.путь.utf8)]?.полнотаПроверена != true {
                            препятствие("не-проверены-ссылки", [член.путь]); вид = .препятствие
                        }
                    }
                }
            } else if !неподвижная {
                препятствие("несовместимые-типы-назначения", исходные); вид = .препятствие
            }
            группы.append(.init(целевой: цель, исходные: исходные, вид: вид))
        }
        let файловыеЦели = Set(назначения.filter { $0.value.contains(where: { $0.вид != .каталог }) }.keys)
        for группа in группы {
            var предок = (группа.целевой as NSString).deletingLastPathComponent
            while !предок.isEmpty {
                if файловыеЦели.contains(Data(предок.utf8)) { препятствие("файловый-префикс", [предок, группа.целевой]) }
                предок = (предок as NSString).deletingLastPathComponent
            }
        }
        let алиасы = Dictionary(grouping: группы.map(\.целевой), by: ключКоллизии)
        for пути in алиасы.values where пути.count > 1 { препятствие("коллизия-регистра-или-Unicode", пути) }
        проверитьАлиасы(группы.map(\.целевой), код: "коллизия-целевых-компонентов")
        return ПланОбщейМиграции(основа: основа, корни: корни.sorted { порядок($0.исходный, $1.исходный) }, отображения: отображения, документы: документыПлана, группы: группы,
            препятствия: препятствия.sorted { $0.код == $1.код ? порядок($0.пути.joined(separator: "\0"), $1.пути.joined(separator: "\0")) : порядок($0.код, $1.код) },
            снимокSHA256: хэш(try кодировщик.encode(упорядоченные)))
    }

    static func байты(_ план: ПланОбщейМиграции) throws -> Data {
        let кодировщик = JSONEncoder(); кодировщик.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(план) + Data([10])
    }

    static func сверить(_ сохранённый: Data, sha256: String, текущий: ПланОбщейМиграции) throws {
        guard хэш(сохранённый) == sha256, try байты(текущий) == сохранённый else { throw ОтказОбщейМиграции.условие("дрейф-плана") }
    }

    static func хэш(_ байты: Data) -> String { SHA256.hash(data: байты).map { String(format: "%02x", $0) }.joined() }

    private static func порядок(_ левый: String, _ правый: String) -> Bool { левый.utf8.lexicographicallyPrecedes(правый.utf8) }
    private static func вложен(_ путь: String, в корне: String) -> Bool { Data(путь.utf8) == Data(корне.utf8) || Data(путь.utf8).starts(with: Data((корне + "/").utf8)) }
    private static func ключКоллизии(_ путь: String) -> Data { Data(путь.precomposedStringWithCanonicalMapping.folding(options: [.caseInsensitive], locale: Locale(identifier: "en_US_POSIX")).precomposedStringWithCanonicalMapping.utf8) }
    private static func проверитьПуть(_ путь: String) throws {
        guard !путь.isEmpty, путь.utf8.count <= 1024, !путь.contains("\\"),
              !путь.unicodeScalars.contains(where: { $0.value < 32 || $0.value == 127 }),
              ИменаПутей.компоненты(путь, сохранятьПустые: true).allSatisfy({ !$0.isEmpty && $0 != "." && $0 != ".." && $0.lowercased() != ".git" && $0.utf8.count <= 255 }) else { throw ОтказОбщейМиграции.условие("небезопасный-путь") }
    }
}

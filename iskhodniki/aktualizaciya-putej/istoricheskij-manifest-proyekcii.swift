struct ОпораИсторическогоМанифеста: Codable, Sendable {
    var коммит: String
    var путь: String
    var объект: String
    var хэш: String
}
struct ИсторическаяПараПроекции: Codable, Equatable, Sendable {
    var номерЗаписи: Int
    var исходныйПуть: String
    var производныйПуть: String
    var режим: String
    var размерИсторическогоИсточника: Int
    var хэшИсторическогоИсточника: String
    var хэшИсторическойЦели: String
    var действиеСодержимого: String
}
struct СверкаИсторическойПары: Codable, Equatable, Sendable {
    var пара: ИсторическаяПараПроекции
    var исходникСовпал: Bool
    var проекцияСовпала: Bool
    var препятствия: [String]
    var привязкаКоммитаПроверена = false
    var якорьПроверен = false
    var перенаправлениеРазрешено = false
}
struct ИндексИсторическойПроекции {
    let опора: ОпораИсторическогоМанифеста
    let хэшПлана: String
    let хэшИнвентаря: String
    let хэшПолитикиКанонический: String
    let статистика: СтатистикаJSONПроекции
    let пары: [ИсторическаяПараПроекции]
    let привязкаКоммитаПроверена = false
    let семантикаПолитикиПроверена = false
    fileprivate let поЦели: [Data: Int]
    fileprivate init(опора: ОпораИсторическогоМанифеста, хэшПлана: String, хэшИнвентаря: String, хэшПолитикиКанонический: String,
        статистика: СтатистикаJSONПроекции, пары: [ИсторическаяПараПроекции], поЦели: [Data: Int]) {
        self.опора = опора; self.хэшПлана = хэшПлана; self.хэшИнвентаря = хэшИнвентаря; self.хэшПолитикиКанонический = хэшПолитикиКанонический
        self.статистика = статистика; self.пары = пары; self.поЦели = поЦели
    }
    func найти(_ точнаяЦель: String) -> ИсторическаяПараПроекции? {
        поЦели[Data(точнаяЦель.utf8)].map { пары[$0] }
    }
    func сверить(_ точнаяЦель: String, хэшТекущегоИсточника: String?, режимТекущегоИсточника: String?, размерТекущегоИсточника: Int?,
        хэшТекущейПроекции: String?, режимТекущейПроекции: String?, естьФрагмент: Bool) -> СверкаИсторическойПары? {
        guard let пара = найти(точнаяЦель) else { return nil }
        let источник = хэшТекущегоИсточника == пара.хэшИсторическогоИсточника && режимТекущегоИсточника == пара.режим && размерТекущегоИсточника == пара.размерИсторическогоИсточника
        let проекция = хэшТекущейПроекции == пара.хэшИсторическойЦели && режимТекущейПроекции == пара.режим
        var причины: [String] = []
        if !источник { причины.append("не-совпал-текущий-источник") }
        if !проекция { причины.append("не-совпала-текущая-проекция") }
        if естьФрагмент { причины.append("нет-доказательства-якоря") }
        причины.append("нет-допуска-перенаправления")
        return .init(пара: пара, исходникСовпал: источник, проекцияСовпала: проекция, препятствия: причины)
    }
}

enum ИсторическийМанифестПроекции {
    static func прочитать(_ данные: Data, опора: ОпораИсторическогоМанифеста) throws -> ИндексИсторическойПроекции {
        guard данные.count <= 33_554_432, верныйХэш(опора.хэш), хэшПутей(данные) == опора.хэш,
              шестнадцатеричный(опора.коммит, длина: 40), шестнадцатеричный(опора.объект, длина: 40),
              Data(опора.путь.utf8) == Data(путьМанифеста.utf8) else { throw ОтказКорпусаСсылок.условие("не-закреплён-исторический-манифест") }
        var гитХэш = Insecure.SHA1(); гитХэш.update(data: Data("blob \(данные.count)\0".utf8)); гитХэш.update(data: данные)
        guard гитХэш.finalize().map({ String(format: "%02x", $0) }).joined() == опора.объект else { throw ОтказКорпусаСсылок.условие("не-совпал-blob-манифеста") }
        var числоЗаписей = 0
        let статистика = try СинтаксисБольшогоМанифестаПроекции.проверить(данные) { путь, ключи in
            let части = путь.split(separator: "/").map(String.init)
            if путь.isEmpty { try проверитьКлючи(ключи, корневыеКлючи) }
            else if Data(путь.utf8) == Data("/исходный_снимок".utf8) { try проверитьКлючи(ключи, ["хэш_инвентаря", "хэш_политики"]) }
            else if Data(путь.utf8) == Data("/преобразование".utf8) { try проверитьКлючи(ключи, ["ревизия", "исходная_письменность", "целевая_письменность", "таблица", "метод"]) }
            else if части.count == 2, Data(части[0].utf8) == Data("записи".utf8), Int(части[1]) != nil {
                числоЗаписей += 1
                guard числоЗаписей <= 16_384 else { throw ОтказКорпусаСсылок.условие("предел-записей-проекции") }
                try проверитьКлючи(ключи, ключиЗаписи)
            } else if части.count == 4, Data(части[0].utf8) == Data("записи".utf8), Data(части[2].utf8) == Data("компоненты_пути".utf8) {
                try проверитьКлючи(ключи, ["исходный", "целевая_основа", "сохранённое_расширение", "целевой", "изменён"])
            }
        }
        let вход = try JSONDecoder().decode(ДокументИсторическойПроекции.self, from: Data(данные))
        guard Data(вход.схема.utf8) == Data("fum.манифест-братиславской-проекции.2".utf8), вход.исходнаяОбласть == ".",
              Data(вход.производноеПространство.utf8) == Data("Proyekcii".utf8), Data(вход.целеваяОбласть.utf8) == Data("Proyekcii/Bratislavskaya-pamyatj".utf8),
              Data(вход.кореньФайлов.utf8) == Data(кореньФайлов.utf8), Data(вход.путьМанифеста.utf8) == Data(путьМанифеста.utf8),
              вход.исключённыеПрефиксы.map({ Data($0.utf8) }) == [".git", "Подузлы", "Proyekcii"].map({ Data($0.utf8) }),
              Data(вход.пустыеКаталоги.utf8) == Data("не_включаются_в_инвентарь_репозитория".utf8), (1...16_384).contains(вход.записи.count), вход.записи.count == числоЗаписей,
              вход.преобразование.ревизия == "837e2ce107b97ee7b9d3344c9fe99142281fe393", вход.преобразование.исходнаяПисьменность == "Cyrl",
              вход.преобразование.целеваяПисьменность == "Latn", вход.преобразование.таблица == "ru", вход.преобразование.метод == "applyingTransform"
        else { throw ОтказКорпусаСсылок.условие("неизвестный-профиль-исторической-проекции") }
        let планХэш = try снятьХэш(вход.хэшПлана), политикаХэш = try снятьХэш(вход.хэшПолитики), инвентарьХэш = try снятьХэш(вход.исходныйСнимок.хэшИнвентаря)
        guard try снятьХэш(вход.исходныйСнимок.хэшПолитики) == политикаХэш else { throw ОтказКорпусаСсылок.условие("разные-политики-исторического-снимка") }
        var пары: [ИсторическаяПараПроекции] = [], поЦели: [Data: Int] = [:], исходные: Set<Data> = [], целевые: Set<Data> = []
        var алиасыИсточников: [Data: Data] = [:], алиасыЦелей: [Data: Data] = [:]
        var каталогиИсточников: Set<Data> = [], каталогиЦелей: Set<Data> = []
        let исключённыеКорни = Set(вход.исключённыеПрефиксы.map { ИменаПутей.ключКоллизии($0) })
        for (номер, запись) in вход.записи.enumerated() {
            try проверитьПуть(запись.исходныйПуть, алиасы: &алиасыИсточников, листья: исходные, каталоги: &каталогиИсточников)
            try проверитьПуть(запись.целевойПуть, алиасы: &алиасыЦелей, листья: целевые, каталоги: &каталогиЦелей)
            guard let первый = ИменаПутей.компоненты(запись.исходныйПуть).first,
                  !исключённыеКорни.contains(ИменаПутей.ключКоллизии(String(первый))), Data(запись.тип.utf8) == Data("обычный_файл".utf8),
                  ["100644", "100755"].contains(запись.режим), запись.размерИсточника >= 0, !запись.причинаДействия.isEmpty,
                  исходные.insert(Data(запись.исходныйПуть.utf8)).inserted, целевые.insert(Data(запись.целевойПуть.utf8)).inserted,
                  классы.contains(Data(запись.классСодержимого.utf8)), действия.contains(Data(запись.действиеСодержимого.utf8)) else { throw ОтказКорпусаСсылок.условие("повторная-или-неверная-историческая-запись") }
            let исходныеЧасти = ИменаПутей.компоненты(запись.исходныйПуть).map { Data($0.utf8) }
            guard запись.компонентыПути.count == исходныеЧасти.count else { throw ОтказКорпусаСсылок.условие("неполные-компоненты-исторического-пути") }
            var целевыеЧасти: [String] = []
            for (часть, исходная) in zip(запись.компонентыПути, исходныеЧасти) {
                try ИменаПутей.проверитьПуть(часть.целевой)
                guard !часть.целевой.utf8.contains(47), Data(часть.исходный.utf8) == исходная,
                      Data(часть.целевой.utf8) == Data((часть.целеваяОснова + часть.сохранённоеРасширение).utf8),
                      часть.изменён == (Data(часть.исходный.utf8) != Data(часть.целевой.utf8)) else { throw ОтказКорпусаСсылок.условие("не-согласованы-компоненты-исторического-пути") }
                целевыеЧасти.append(часть.целевой)
            }
            guard Data(запись.целевойПуть.utf8) == Data((кореньФайлов + "/" + целевыеЧасти.joined(separator: "/")).utf8) else { throw ОтказКорпусаСсылок.условие("не-совпала-историческая-цель") }
            let исходныйХэш = try снятьХэш(запись.хэшИсточника), целевойХэш = try снятьХэш(запись.хэшЦели)
            guard запись.действиеСодержимого != "сохранить_байты" || исходныйХэш == целевойХэш else { throw ОтказКорпусаСсылок.условие("изменились-сохраняемые-исторические-байты") }
            поЦели[Data(запись.целевойПуть.utf8)] = пары.count
            пары.append(.init(номерЗаписи: номер, исходныйПуть: запись.исходныйПуть, производныйПуть: запись.целевойПуть, режим: запись.режим,
                размерИсторическогоИсточника: запись.размерИсточника, хэшИсторическогоИсточника: исходныйХэш, хэшИсторическойЦели: целевойХэш, действиеСодержимого: запись.действиеСодержимого))
        }
        let выходы = вход.итоговыеФайлы.map { Data($0.utf8) }, ожидаемые = Set(поЦели.keys).union([Data(путьМанифеста.utf8)])
        guard выходы.count == ожидаемые.count, Set(выходы) == ожидаемые, выходы == выходы.sorted(by: { $0.lexicographicallyPrecedes($1) }) else { throw ОтказКорпусаСсылок.условие("неполный-исторический-набор-выходов") }
        return .init(опора: опора, хэшПлана: планХэш, хэшИнвентаря: инвентарьХэш, хэшПолитикиКанонический: политикаХэш, статистика: статистика, пары: пары, поЦели: поЦели)
    }

    private static let кореньФайлов = "Proyekcii/Bratislavskaya-pamyatj/fajlyi"
    private static let путьМанифеста = "Proyekcii/Bratislavskaya-pamyatj/manifest-proiskhozhdeniya-v2.json"
    private static let корневыеКлючи = ["схема", "хэш_плана", "хэш_политики", "исходный_снимок", "исходная_область", "производное_пространство", "целевая_область", "корень_файлов", "путь_манифеста", "исключённые_префиксы", "преобразование", "форматная_политика", "пустые_каталоги", "записи", "итоговые_файлы"]
    private static let ключиЗаписи = ["исходный_путь", "целевой_путь", "компоненты_пути", "тип", "режим", "размер_источника", "хэш_источника", "хэш_цели", "класс_содержимого", "действие_содержимого", "причина_действия"]
    private static let классы = Set(["машинные_данные", "прочий_точный_формат", "разметка", "код", "разметка_с_дословным_блоком", "двоичный_или_нетекстовый", "машинный_шаблон", "дословный_источник"].map { Data($0.utf8) })
    private static let действия = Set(["сохранить_байты", "преобразовать_структурно", "преобразовать_разметку_с_дословным_блоком"].map { Data($0.utf8) })
    private static func проверитьКлючи(_ фактические: Set<Data>, _ ожидаемые: [String]) throws {
        guard фактические == Set(ожидаемые.map { Data($0.utf8) }) else { throw ОтказКорпусаСсылок.условие("неизвестные-поля-манифеста-проекции") }
    }
    private static func шестнадцатеричный(_ строка: String, длина: Int) -> Bool {
        строка.utf8.count == длина && строка.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
    private static func верныйХэш(_ строка: String) -> Bool { шестнадцатеричный(строка, длина: 64) }
    private static func снятьХэш(_ строка: String) throws -> String {
        guard строка.hasPrefix("sha256:"), верныйХэш(String(строка.dropFirst(7))) else { throw ОтказКорпусаСсылок.условие("неверный-исторический-SHA256") }
        return String(строка.dropFirst(7))
    }
    private static func проверитьПуть(_ путь: String, алиасы: inout [Data: Data], листья: Set<Data>, каталоги: inout Set<Data>) throws {
        guard путь.utf8.count <= 1024 else { throw ОтказКорпусаСсылок.условие("предел-исторического-пути") }
        try ИменаПутей.проверитьПуть(путь)
        var префикс = ""
        let части = ИменаПутей.компоненты(путь)
        guard !каталоги.contains(Data(путь.utf8)) else { throw ОтказКорпусаСсылок.условие("файл-был-каталогом-исторического-пути") }
        for (номер, часть) in части.enumerated() {
            префикс += (префикс.isEmpty ? "" : "/") + часть
            let точный = Data(префикс.utf8), ключ = ИменаПутей.ключКоллизии(префикс)
            guard алиасы[ключ] == nil || алиасы[ключ] == точный else { throw ОтказКорпусаСсылок.условие("алиасы-компонентов-исторического-пути") }
            алиасы[ключ] = точный
            if номер + 1 < части.count {
                guard !листья.contains(точный) else { throw ОтказКорпусаСсылок.условие("файл-стал-предком-исторического-пути") }
                каталоги.insert(точный)
            }
        }
    }
}


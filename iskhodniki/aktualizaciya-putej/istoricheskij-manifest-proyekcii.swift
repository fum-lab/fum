// Политика сохраняет происхождение через hash всего манифеста. Её смысл
// этим историческим индексом не проверяется и допуска перенаправления не даёт.
private struct НепровереннаяФорматнаяПолитика: Decodable {
    private struct Ключ: CodingKey { var stringValue: String; var intValue: Int?; init?(stringValue значение: String) { self.stringValue = значение }; init?(intValue значение: Int) { return nil } }
    init(from декодер: Decoder) throws { _ = try декодер.container(keyedBy: Ключ.self) }
}

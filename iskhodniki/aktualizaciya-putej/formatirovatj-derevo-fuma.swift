public enum ФорматировщикПутейFUMA {
    public static let версия = "fum.fuma.path-format.2"
    public static let версияКарты = "fum.fuma.path-component-map.1"
    public static let версияСсылок = "fum.fuma.live-reference-policy.1"
    public static let версияИсключений = "fum.fuma.path-exclusions.1"
    public static let версияШаблонов = "fum.fuma.templates.none.1"
    public static let исходныйКорень = "Приложения/FUMA"
    public static let целевойКорень = "fuma"

    public static func режимКоманды(аргументы: [String]) -> РежимКомандыФорматированияFUMA {
        if аргументы == ["--version"] { return .версия }
        if аргументы == ["--plan"] { return .план }
        if аргументы == ["--apply"] {
            return .отказ("Применение закрыто до проверенного восстановления после прерывания")
        }
        return .отказ("Допустимы только --plan, --apply или --version")
    }

    /// Предварительная классификация не предоставляет полномочий на применение.
    public static func состояние(версияМаркера: String?, старыйКореньСуществует: Bool) -> СостояниеФорматированияПутейFUMA {
        if старыйКореньСуществует {
            return версияМаркера == nil ? .применить : .отказ("Старый и форматированный корни существуют одновременно")
        }
        guard let версияМаркера else { return .отказ("Старый корень отсутствует, маркер версии не найден") }
        return версияМаркера == версия
            ? .отказ("Одна версия маркера не подтверждает происхождение и состав дерева")
            : .отказ("Версия маркера не совпадает с версией форматировщика")
    }

    public static func составитьКарту(
        путей исходника: [String]
    ) async throws -> КартаПутейFUMA {
        try await составитьКарту(путей: исходника) { компонент in
            let имя = try await ПубличныйФасадИмён.канонизировать(компонент)
            return РезультатИмениКомпонентаFUMA(
                значение: имя.значение, происхождение: имя.происхождение)
        }
    }

    private static func составитьКарту(
        путей исходника: [String],
        канонизировать: @escaping @Sendable (String) async throws -> РезультатИмениКомпонентаFUMA
    ) async throws -> КартаПутейFUMA {
        var представления: [String: Data] = [:]
        var представленияКомпонентов: [String: Data] = [:]
        for путь in исходника {
            let байты = Array(путь.utf8)
            var началоКомпонента = 0
            for граница in 0...байты.count where граница == байты.count || байты[граница] == 47 {
                let байтыПрефикса = Data(байты[..<граница])
                let байтыКомпонента = Data(байты[началоКомпонента..<граница])
                guard let префикс = String(data: байтыПрефикса, encoding: .utf8),
                      let компонент = String(data: байтыКомпонента, encoding: .utf8) else {
                    throw ОшибкаФорматированияПутейFUMA.неоднозначноеПредставлениеПути(путь)
                }
                if let прежниеБайты = представления[префикс], прежниеБайты != байтыПрефикса {
                    throw ОшибкаФорматированияПутейFUMA.неоднозначноеПредставлениеПути(префикс)
                }
                if let прежниеБайты = представленияКомпонентов[компонент], прежниеБайты != байтыКомпонента {
                    throw ОшибкаФорматированияПутейFUMA.неоднозначноеПредставлениеПути(префикс)
                }
                представления[префикс] = байтыПрефикса
                представленияКомпонентов[компонент] = байтыКомпонента
                началоКомпонента = граница + 1
            }
        }
        let исходныеПути = Array(Set(исходника)).sorted()
        guard !исходныеПути.isEmpty else { throw ОшибкаФорматированияПутейFUMA.пустойИсходник }

        var кэш: [String: РезультатИмениКомпонентаFUMA] = [:]
        var картаКомпонентов: [String: СопоставлениеКомпонентаFUMA] = [:]

        func имя(_ компонент: String) async throws -> РезультатИмениКомпонентаFUMA {
            if let готовое = кэш[компонент] { return готовое }
            let результат: РезультатИмениКомпонентаFUMA
            let причина: String
            if компонент == "Package.swift" || компонент == "AGENTS.md" {
                результат = .init(значение: компонент, происхождение: nil)
                причина = "точное служебное имя сохраняется"
            } else {
                результат = try await канонизировать(компонент)
                причина = "ПубличныйФасадИмён"
            }
            guard !результат.значение.isEmpty, !результат.значение.contains("/"),
                  результат.значение != ".", результат.значение != ".." else {
                throw ОшибкаФорматированияПутейFUMA.недопустимоеИмя(компонент, результат.значение)
            }
            if причина == "ПубличныйФасадИмён", результат.происхождение == nil {
                throw ОшибкаФорматированияПутейFUMA.нетПроисхожденияИмени(компонент)
            }
            кэш[компонент] = результат
            картаКомпонентов[компонент] = СопоставлениеКомпонентаFUMA(
                исходное: компонент, целевое: результат.значение, причина: причина,
                происхождение: результат.происхождение)
            return результат
        }

        let начальныеКомпоненты = ["Приложения", "FUMA", целевойКорень]
        for компонент in начальныеКомпоненты { _ = try await имя(компонент) }
        guard кэш["FUMA"]?.значение == целевойКорень,
              кэш[целевойКорень]?.значение == целевойКорень else {
            throw ОшибкаФорматированияПутейFUMA.кореньНеКаноничен
        }

        var отображенияПутей: [String: String] = [исходныйКорень: целевойКорень]
        for исходныйПуть in исходныеПути {
            guard исходныйПуть.hasPrefix(исходныйКорень + "/") else {
                throw ОшибкаФорматированияПутейFUMA.путьВнеИсточника(исходныйПуть)
            }
            let компонентыПути = исходныйПуть.split(separator: "/", omittingEmptySubsequences: false).map(String.init)
            guard компонентыПути.count >= 3,
                  компонентыПути[0] == "Приложения", компонентыПути[1] == "FUMA",
                  компонентыПути.allSatisfy({ !$0.isEmpty && $0 != "." && $0 != ".." }) else {
                throw ОшибкаФорматированияПутейFUMA.путьВнеИсточника(исходныйПуть)
            }

            var исходныйПрефикс = исходныйКорень
            var целевойПрефикс = целевойКорень
            for компонент in компонентыПути.dropFirst(2) {
                let целевоеИмя = try await имя(компонент)
                исходныйПрефикс += "/" + компонент
                целевойПрефикс += "/" + целевоеИмя.значение
                if let прежнее = отображенияПутей[исходныйПрефикс], прежнее != целевойПрефикс {
                    throw ОшибкаФорматированияПутейFUMA.неоднозначнаяКарта(исходныйПрефикс)
                }
                отображенияПутей[исходныйПрефикс] = целевойПрефикс
            }
        }

        let sortedMappings = отображенияПутей.map { ЗаписьПутиFUMA(исходное: $0.key, целевое: $0.value) }
            .sorted { $0.исходное < $1.исходное }
        return КартаПутейFUMA(
            версия: версия,
            исходныйКорень: исходныйКорень,
            целевойКорень: целевойКорень,
            компоненты: картаКомпонентов.values.sorted { $0.исходное < $1.исходное },
            пути: sortedMappings)
    }

    /// Делегирует проверку топологии общему планировщику миграции.
    /// Сопоставление компонентов остаётся FUMA-специфичным; дублирующего collision planner здесь нет.
    public static func проверитьТопологию(
        карты: КартаПутейFUMA,
        файлы: [ЗаписьИсходногоФайлаДереваFUMA],
        контекст: КонтекстПроверкиДереваFUMA
    ) throws -> [ПрепятствиеТопологииFUMA] {
        let основа = ОсноваОбщейМиграции(
            корневаяЗадача: контекст.корневаяЗадача,
            владелец: контекст.владелец,
            ветка: контекст.ветка,
            коммит: контекст.коммит,
            дерево: контекст.дерево,
            индексSHA256: контекст.индексSHA256)
        var узлы: [УзелОбщейМиграции] = []
        for файл in файлы {
            guard let назначение = карты.целевойПутьДляСсылки(файл.путь) else {
                throw ОшибкаФорматированияПутейFUMA.путьВнеИсточника(файл.путь)
            }
            узлы.append(.init(
                путь: назначение,
                вид: .файл,
                режим: файл.режимGit,
                объект: файл.объектGit,
                байты: файл.байты,
                дословный: true))
        }
        let план = try ОбщийПланировщикПутей.построить(
            основа: основа, ожидаемаяОснова: основа, узлы: узлы, корни: [])
        let препятствия = план.препятствия.map { ПрепятствиеТопологииFUMA(код: $0.код, пути: $0.пути) }
        let дубликатыЛистьев = план.группы
            .filter { $0.исходные.count > 1 && $0.вид != .объединениеКаталогов }
            .map { ПрепятствиеТопологииFUMA(код: "повторное-назначение", пути: $0.исходные + [$0.целевой]) }
        return (препятствия + дубликатыЛистьев).sorted {
            $0.код == $1.код ? $0.пути.joined(separator: "\0") < $1.пути.joined(separator: "\0") : $0.код < $1.код
        }
    }

}

public enum ОшибкаФорматированияПутейFUMA: Error, CustomStringConvertible, Sendable {
    case пустойИсходник
    case путьВнеИсточника(String)
    case недопустимоеИмя(String, String)
    case кореньНеКаноничен
    case неоднозначнаяКарта(String)
    case неоднозначноеПредставлениеПути(String)
    case нетПроисхожденияИмени(String)

    public var description: String {
        switch self {
        case .пустойИсходник: "Исходное дерево FUMA пусто"
        case .путьВнеИсточника(let путь): "Путь находится вне \(ФорматировщикПутейFUMA.исходныйКорень): \(путь)"
        case .недопустимоеИмя(let исходное, let целевое): "Недопустимое имя компонента \(исходное) → \(целевое)"
        case .кореньНеКаноничен: "Публичный фасад не подтвердил целевой корень fuma"
        case .неоднозначнаяКарта(let путь): "Компонент получил разные назначения: \(путь)"
        case .неоднозначноеПредставлениеПути(let путь): "Путь имеет разные байтовые представления: \(путь)"
        case .нетПроисхожденияИмени(let компонент): "Нет происхождения Names для компонента: \(компонент)"
        }
    }
}

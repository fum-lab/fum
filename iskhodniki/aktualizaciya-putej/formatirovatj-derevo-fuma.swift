public enum ОшибкаРазбораВыводаПутейFUMA: Error, Equatable, Sendable {
    case неполноеОбрамление
    case невернаяЗаписьИндекса
    case невернаяКодировкаПути
}

/// Разбирает переданные байты; происхождение Git-вывода проверяется отдельно.
public enum РазборВыводаПутейFUMA {
    public static func пути(_ данные: Data) throws -> [String] {
        try рамки(данные).map { try путьИзБайтов($0) }
    }

    public static func записиИндекса(_ данные: Data) throws -> [ЗаписьИндексаПутейFUMA] {
        try байтовыеЗаписиИндекса(данные).map { запись in
            guard запись.стадия == 0 else {
                throw ОшибкаРазбораВыводаПутейFUMA.невернаяЗаписьИндекса
            }
            return ЗаписьИндексаПутейFUMA(
                путь: try путьИзБайтов(запись.путь), режим: запись.режим, объект: запись.объект)
        }
    }

    /// Разбор SHA-1 вывода `git ls-files --stage -z`, включая конфликтные стадии.
    /// Байты пути не декодируются; источник вывода и формат объектов проверяются отдельно.
    public static func байтовыеЗаписиИндекса(_ данные: Data) throws -> [БайтоваяЗаписьИндексаFUMA] {
        try рамки(данные).map { запись in
            let байты = Array(запись)
            guard let граница = байты.firstIndex(of: 9),
                  let метаданные = String(bytes: байты[..<граница], encoding: .ascii) else {
                throw ОшибкаРазбораВыводаПутейFUMA.невернаяЗаписьИндекса
            }
            let поля = метаданные.split(separator: " ", omittingEmptySubsequences: false)
            guard поля.count == 3,
                  ["100644", "100755", "120000", "160000", "040000"].contains(String(поля[0])),
                  поля[1].utf8.count == 40,
                  поля[1].utf8.allSatisfy({ (48...57).contains($0) || (97...102).contains($0) }),
                  ["0", "1", "2", "3"].contains(String(поля[2])),
                  let стадия = UInt8(поля[2]) else {
                throw ОшибкаРазбораВыводаПутейFUMA.невернаяЗаписьИндекса
            }
            let путь = Data(байты[(граница + 1)...])
            guard !путь.isEmpty else { throw ОшибкаРазбораВыводаПутейFUMA.невернаяЗаписьИндекса }
            return БайтоваяЗаписьИндексаFUMA(
                путь: путь, режим: String(поля[0]), объект: String(поля[1]), стадия: стадия)
        }
    }

    private static func рамки(_ данные: Data) throws -> [Data] {
        guard !данные.isEmpty else { return [] }
        guard данные.count > 1, данные.last == 0 else {
            throw ОшибкаРазбораВыводаПутейFUMA.неполноеОбрамление
        }
        let фрагменты = данные.dropLast().split(separator: 0, omittingEmptySubsequences: false)
        guard !фрагменты.contains(where: { $0.isEmpty }) else {
            throw ОшибкаРазбораВыводаПутейFUMA.неполноеОбрамление
        }
        return фрагменты.map { Data($0) }
    }

    private static func путьИзБайтов(_ данные: Data) throws -> String {
        guard !данные.isEmpty, let путь = String(data: данные, encoding: .utf8),
              Data(путь.utf8) == данные else {
            throw ОшибкаРазбораВыводаПутейFUMA.невернаяКодировкаПути
        }
        return путь
    }
}

public struct КартаПутейFUMA: Codable, Equatable, Sendable {
    public let версия: String
    public let исходныйКорень: String
    public let целевойКорень: String
    public let компоненты: [СопоставлениеКомпонентаFUMA]
    public let пути: [ЗаписьПутиFUMA]

    public func целевойПутьДляСсылки(_ исходныйПуть: String) -> String? {
        let совпадения = пути
            .filter { исходныйПуть == $0.исходное || исходныйПуть.hasPrefix($0.исходное + "/") }
            .sorted { $0.исходное.utf8.count > $1.исходное.utf8.count }
        guard let совпадение = совпадения.first else { return nil }
        return совпадение.целевое + String(исходныйПуть.dropFirst(совпадение.исходное.count))
    }

    /// Переписывает только точные известные пути и их продолжения; идентификаторы и соседние имена не меняются.
    public func переписатьСсылкиВ(_ текст: String) -> String {
        String(decoding: переписатьБайты(Data(текст.utf8)), as: UTF8.self)
    }

    /// Побайтовая замена сохраняет не затронутые фрагменты текста, переводы строк и кодировки UTF-8.
    public func переписатьБайты(_ исходныеБайты: Data) -> Data {
        переписатьБайтыСПодсчётом(исходныеБайты).байты
    }

    public func переписатьБайтыСПодсчётом(_ исходныеБайты: Data) -> (байты: Data, числоЗамен: Int) {
        var результат = исходныеБайты
        var числоЗамен = 0
        for запись in пути.sorted(by: { $0.исходное.utf8.count > $1.исходное.utf8.count }) {
            let старыеБайты = Data(запись.исходное.utf8)
            let новыеБайты = Data(запись.целевое.utf8)
            guard !старыеБайты.isEmpty else { continue }
            var обновлённыеБайты = Data()
            var курсор = 0
            while курсор < результат.count,
                  let диапазон = результат.range(of: старыеБайты, options: [], in: курсор..<результат.count) {
                let границаДо = диапазон.lowerBound == 0 || Self.разделительДо(результат[диапазон.lowerBound - 1])
                let продолжениеСтарогоКорня = запись.исходное == ФорматировщикПутейFUMA.исходныйКорень
                    && диапазон.upperBound < результат.count
                    && результат[диапазон.upperBound] == 47
                    && диапазон.upperBound + 1 < результат.count
                    && !Self.разделительПосле(результат[диапазон.upperBound + 1])
                let границаПосле = !продолжениеСтарогоКорня && (диапазон.upperBound == результат.count
                    || Self.разделительПосле(результат[диапазон.upperBound]))
                guard границаДо && границаПосле else {
                    let конец = min(диапазон.lowerBound + 1, результат.count)
                    обновлённыеБайты.append(результат[курсор..<конец])
                    курсор = конец
                    continue
                }
                обновлённыеБайты.append(результат[курсор..<диапазон.lowerBound])
                обновлённыеБайты.append(новыеБайты)
                курсор = диапазон.upperBound
                числоЗамен += 1
            }
            if курсор < результат.count {
                обновлённыеБайты.append(результат[курсор..<результат.count])
            }
            if !обновлённыеБайты.isEmpty {
                результат = обновлённыеБайты
            }
        }
        return (результат, числоЗамен)
    }

    private static func разделительДо(_ байт: UInt8) -> Bool {
        [9, 10, 13, 32, 34, 39, 40, 44, 58, 60, 61, 91, 96, 123].contains(байт) || байт == 47
    }

    private static func разделительПосле(_ байт: UInt8) -> Bool {
        [9, 10, 13, 32, 34, 39, 41, 44, 58, 59, 62, 63, 91, 93, 96, 123, 125].contains(байт) || байт == 47
    }
}


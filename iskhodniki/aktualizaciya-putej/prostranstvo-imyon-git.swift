import CryptoKit

enum ВидЛистаДереваGit: String, Codable, Sendable { case файл, символическаяСсылка, внешняяЗависимость }
struct ЛистДереваGit: Equatable, Sendable {
    var путь: Data
    var режим: String
    var объект: String
    var вид: ВидЛистаДереваGit
}
struct ПроверенноеПространствоИмёнGit: Sendable {
    let дерево: String
    let хэшСырогоПеречня: String
    let хэшИндекса: String
    let листья: [ЛистДереваGit]
    let каталоги: Set<Data>
    let коллизии: [ПрепятствиеОбщейМиграции]
    let содержимоеОбъектовПроверено = false
    let файловаяСистемаПроверена = false
    let применениеРазрешено = false
    fileprivate init(дерево: String, хэшСырогоПеречня: String, хэшИндекса: String, листья: [ЛистДереваGit], каталоги: Set<Data>, коллизии: [ПрепятствиеОбщейМиграции]) {
        self.дерево = дерево; self.хэшСырогоПеречня = хэшСырогоПеречня; self.хэшИндекса = хэшИндекса; self.листья = листья; self.каталоги = каталоги; self.коллизии = коллизии
    }
}
enum ПространствоИмёнGit {
    static func проверить(переченьДерева: Data, индекс: Data, ожидаемоеДерево: String, ожидаемыйХэшИндекса: String) throws -> ПроверенноеПространствоИмёнGit {
        guard переченьДерева.count <= 16_777_216, индекс.count <= 16_777_216,
              шестнадцатеричный(ожидаемоеДерево, длина: 40), шестнадцатеричный(ожидаемыйХэшИндекса, длина: 64),
              хэшПутей(индекс) == ожидаемыйХэшИндекса,
              (переченьДерева.isEmpty || переченьДерева.last == 0), (индекс.isEmpty || индекс.last == 0) else { throw ОтказКорпусаСсылок.условие("неверные-опоры-пространства-Git") }
        var листья: [ЛистДереваGit] = []
        for строка in переченьДерева.split(separator: 0, omittingEmptySubsequences: false).dropLast() {
            guard !строка.isEmpty, листья.count < 100_000, let текст = String(data: строка, encoding: .utf8), let табуляция = текст.firstIndex(of: "\t") else { throw ОтказКорпусаСсылок.условие("неверная-строка-дерева-Git") }
            let заголовок = String(текст[..<табуляция]), поля = заголовок.split(separator: " ", omittingEmptySubsequences: false).map(String.init)
            guard поля.count == 3, let вид = вид(режим: поля[0]), поля[1] == (вид == .внешняяЗависимость ? "commit" : "blob"),
                  шестнадцатеричный(поля[2], длина: 40) else { throw ОтказКорпусаСсылок.условие("неверный-тип-mode-OID-дерева-Git") }
            let путь = Data(текст[текст.index(after: табуляция)...].utf8)
            листья.append(.init(путь: путь, режим: поля[0], объект: поля[2], вид: вид))
        }
        // Старый stage0 parser сохраняется общим. Каноническое обрамление
        // этого нового входа проверяется отдельно до сопоставления фактов.
        for строка in индекс.split(separator: 0, omittingEmptySubsequences: false).dropLast() {
            guard !строка.isEmpty, let текст = String(data: строка, encoding: .utf8), let табуляция = текст.firstIndex(of: "\t") else { throw ОтказКорпусаСсылок.условие("неверное-обрамление-stage0") }
            let поля = текст[..<табуляция].split(separator: " ", omittingEmptySubsequences: false)
            guard поля.count == 3, !поля.contains(where: \.isEmpty), поля[2] == "0" else { throw ОтказКорпусаСсылок.условие("не-канонический-stage0") }
        }
        let записиИндекса = try ЧитательДокументовКорпуса.разобратьИндекс(индекс)
        guard записиИндекса.count == листья.count, листья.allSatisfy({ записиИндекса[$0.путь]?.режим == $0.режим && записиИндекса[$0.путь]?.объект == $0.объект }) else { throw ОтказКорпусаСсылок.условие("весь-stage0-не-совпал-с-деревом") }
        let сборка = try собрать(листья)
        let фактическоеДерево = хэшДерева(сборка.корень).map { String(format: "%02x", $0) }.joined()
        guard фактическоеДерево == ожидаемоеДерево else { throw ОтказКорпусаСсылок.условие("не-воспроизведён-Git-tree-OID") }
        return .init(дерево: фактическоеДерево, хэшСырогоПеречня: хэшПутей(переченьДерева), хэшИндекса: ожидаемыйХэшИндекса,
            листья: листья, каталоги: сборка.каталоги, коллизии: сборка.коллизии)
    }
    static func вычислитьДерево(_ листья: [ЛистДереваGit], пределБайтовПрефиксов: Int = 67_108_864) throws -> String {
        try хэшДерева(собрать(листья, пределБайтовПрефиксов: пределБайтовПрефиксов).корень).map { String(format: "%02x", $0) }.joined()
    }

    private final class Узел {
        var лист: ЛистДереваGit?
        var дети: [Data: Узел] = [:]
    }
    private static func собрать(_ листья: [ЛистДереваGit], пределБайтовПрефиксов: Int = 67_108_864) throws -> (корень: Узел, каталоги: Set<Data>, коллизии: [ПрепятствиеОбщейМиграции]) {
        guard листья.count <= 100_000, (0...67_108_864).contains(пределБайтовПрефиксов) else { throw ОтказКорпусаСсылок.условие("предел-листьев-или-префиксов-Git") }
        let корень = Узел(); var каталоги: Set<Data> = [], алиасы: [Data: Set<Data>] = [:], числоУзлов = 1, суммаПутей = 0, суммаПрефиксов = 0
        for лист in листья {
            guard лист.путь.count <= 16_777_216 - суммаПутей, let путь = String(data: лист.путь, encoding: .utf8), вид(режим: лист.режим) == лист.вид,
                  шестнадцатеричный(лист.объект, длина: 40) else { throw ОтказКорпусаСсылок.условие("неверный-лист-Git") }
            суммаПутей += лист.путь.count
            try ИменаПутей.проверитьПуть(путь)
            let части = ИменаПутей.компоненты(путь).map { Data($0.utf8) }
            guard части.count <= 64 else { throw ОтказКорпусаСсылок.условие("предел-глубины-дерева-Git") }
            var текущий = корень, префикс = Data()
            for (номер, имя) in части.enumerated() {
                guard текущий.лист == nil else { throw ОтказКорпусаСсылок.условие("файл-стал-предком-в-дереве-Git") }
                if !префикс.isEmpty { префикс.append(47) }; префикс.append(имя)
                let ключ = ИменаПутей.ключКоллизии(String(decoding: префикс, as: UTF8.self))
                if алиасы[ключ]?.contains(префикс) != true {
                    // Это бюджет сохраняемых данных префиксов, а не RSS.
                    // Повторный folded key у разных raw-алиасов считается консервативно.
                    guard префикс.count <= пределБайтовПрефиксов - суммаПрефиксов,
                          ключ.count <= пределБайтовПрефиксов - суммаПрефиксов - префикс.count else {
                        throw ОтказКорпусаСсылок.условие("предел-байтов-префиксов-Git")
                    }
                    суммаПрефиксов += префикс.count + ключ.count
                    алиасы[ключ, default: []].insert(префикс)
                }
                if номер + 1 < части.count { каталоги.insert(префикс) }
                if текущий.дети[имя] == nil {
                    guard числоУзлов < 500_000 else { throw ОтказКорпусаСсылок.условие("предел-узлов-дерева-Git") }
                    текущий.дети[имя] = Узел(); числоУзлов += 1
                }
                текущий = текущий.дети[имя]!
            }
            guard текущий.лист == nil, текущий.дети.isEmpty else { throw ОтказКорпусаСсылок.условие("повторный-файл-или-каталог-в-дереве-Git") }
            текущий.лист = лист
        }
        let коллизии = алиасы.values.filter { $0.count > 1 }.map { набор in
            ПрепятствиеОбщейМиграции(код: "алиасы-пространства-имён-Git", пути: набор.sorted { $0.lexicographicallyPrecedes($1) }.map { String(decoding: $0, as: UTF8.self) })
        }.sorted { порядокПутей($0.пути.joined(separator: "\0"), $1.пути.joined(separator: "\0")) }
        return (корень, каталоги, коллизии)
    }
    private static func хэшДерева(_ узел: Узел) -> Data {
        var байты = Data()
        let порядок = узел.дети.keys.sorted { левый, правый in
            let л = левый + (узел.дети[левый]!.лист == nil ? Data([47]) : Data())
            let п = правый + (узел.дети[правый]!.лист == nil ? Data([47]) : Data())
            return л.lexicographicallyPrecedes(п)
        }
        for имя in порядок {
            let ребёнок = узел.дети[имя]!
            let режим = ребёнок.лист?.режим ?? "40000"
            let объект = ребёнок.лист.map { декодироватьOID($0.объект) } ?? хэшДерева(ребёнок)
            байты.append(Data((режим + " ").utf8)); байты.append(имя); байты.append(0); байты.append(объект)
        }
        var хэш = Insecure.SHA1(); хэш.update(data: Data("tree \(байты.count)\0".utf8)); хэш.update(data: байты)
        return Data(хэш.finalize())
    }
    private static func вид(режим: String) -> ВидЛистаДереваGit? {
        switch режим {
        case "100644", "100755": .файл
        case "120000": .символическаяСсылка
        case "160000": .внешняяЗависимость
        default: nil
        }
    }
    private static func шестнадцатеричный(_ строка: String, длина: Int) -> Bool {
        строка.utf8.count == длина && строка.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
    private static func декодироватьOID(_ строка: String) -> Data {
        let байты = Array(строка.utf8)
        func цифра(_ знак: UInt8) -> UInt8 { знак <= 57 ? знак - 48 : знак - 87 }
        return Data(stride(from: 0, to: байты.count, by: 2).map { цифра(байты[$0]) * 16 + цифра(байты[$0 + 1]) })
    }
}

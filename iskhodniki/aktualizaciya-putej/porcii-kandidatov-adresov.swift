import Foundation
import CryptoKit

struct ДокументПланаПорций: Sendable {
    let путь: String
    let хэш: String
    let режим: String
    let размер: Int
    let класс: String
    let объект: String?
}
struct ШагПланаПорций: Equatable, Sendable {
    let начало: Int
    let конец: Int
    let байты: Int
    let допускаетОбход: Bool
}
struct ОпорыПланаПорций: Sendable {
    let ожидание: String
    let физическийСнимок: String
    let собственныйИсточник: String
    let контекст: String
    fileprivate init(_ ожидание: String, _ физическийСнимок: String, _ собственныйИсточник: String, _ контекст: String) {
        self.ожидание = ожидание; self.физическийСнимок = физическийСнимок; self.собственныйИсточник = собственныйИсточник; self.контекст = контекст
    }
}
struct ОжидаемаяЗаписьПорции: Sendable {
    let номер: Int
    let документ: ДокументПланаПорций
    let хэшПлана: String
    let опоры: ОпорыПланаПорций
    fileprivate init(номер: Int, документ: ДокументПланаПорций, хэшПлана: String, опоры: ОпорыПланаПорций) {
        self.номер = номер; self.документ = документ; self.хэшПлана = хэшПлана; self.опоры = опоры
    }
}
struct ПланПорцийКандидатов: Sendable {
    let шаги: [ШагПланаПорций]
    let документы: Int
    let байты: Int
    let хэшСостава: String
    private let входы: [ДокументПланаПорций]
    private let опоры: ОпорыПланаПорций
    let внешниеОпорыПроверены = false
    let содержимоеПроверено = false
    let ролиПроверены = false
    let применениеРазрешено = false
    fileprivate init(шаги: [ШагПланаПорций], входы: [ДокументПланаПорций], байты: Int, хэшСостава: String, опоры: ОпорыПланаПорций) {
        self.шаги = шаги; self.документы = входы.count; self.входы = входы; self.байты = байты; self.хэшСостава = хэшСостава; self.опоры = опоры
    }
    func ожидаемаяЗапись(_ номер: Int) throws -> ОжидаемаяЗаписьПорции {
        guard входы.indices.contains(номер) else { throw ОтказСсылокПакета.условие("номер-вне-плана-порций") }
        return .init(номер: номер, документ: входы[номер], хэшПлана: хэшСостава, опоры: опоры)
    }
}
enum ПланировщикПорцийКандидатов {
    static func построить(_ документы: [ДокументПланаПорций], хэшОжидания: String,
        хэшФизическогоСнимка: String, хэшСобственногоИсточника: String, хэшКонтекста: String,
        документовВПорции: Int = 256, байтовВПорции: Int = 16_777_216) throws -> ПланПорцийКандидатов {
        func шестнадцатеричный(_ значение: String, _ длина: Int) -> Bool {
            значение.utf8.count == длина && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
        }
        guard (1...8192).contains(документы.count), (1...256).contains(документовВПорции), (1...16_777_216).contains(байтовВПорции),
              [хэшОжидания, хэшФизическогоСнимка, хэшСобственногоИсточника, хэшКонтекста].allSatisfy({ шестнадцатеричный($0, 64) }) else {
            throw ОтказСсылокПакета.условие("неверные-опоры-или-пределы-порций")
        }
        var хэш = SHA256(), сумма = 0, пути: Set<Data> = []
        func число(_ значение: Int) {
            var длина = UInt64(значение).bigEndian
            withUnsafeBytes(of: &длина) { хэш.update(data: Data($0)) }
        }
        func поле(_ значение: String) { число(значение.utf8.count); хэш.update(data: Data(значение.utf8)) }
        for значение in ["fum.план-порций-кандидатов.1", хэшОжидания, хэшФизическогоСнимка, хэшСобственногоИсточника, хэшКонтекста] { поле(значение) }
        число(документовВПорции); число(байтовВПорции); число(документы.count)
        for документ in документы {
            try ИменаПутей.проверитьПуть(документ.путь)
            guard шестнадцатеричный(документ.хэш, 64), документ.режим.utf8.count == 6, ["100644", "100755"].contains(документ.режим),
                  документ.класс.utf8.count <= 64,
                  (0...33_554_432).contains(документ.размер), документ.размер <= 134_217_728 - сумма,
                  пути.insert(Data(документ.путь.utf8)).inserted else { throw ОтказСсылокПакета.условие("неверная-запись-плана-порций") }
            if Data(документ.класс.utf8) == Data("отслеживаемый".utf8) {
                guard let объект = документ.объект, шестнадцатеричный(объект, 40) else { throw ОтказСсылокПакета.условие("нет-объекта-записи-порций") }
            } else {
                guard Data(документ.класс.utf8) == Data("собственный-неотслеживаемый".utf8), документ.объект == nil else { throw ОтказСсылокПакета.условие("неверный-класс-записи-порций") }
            }
            сумма += документ.размер
            поле(документ.путь); поле(документ.хэш); поле(документ.режим); число(документ.размер)
            поле(документ.класс); поле(документ.объект ?? "")
        }
        var шаги: [ШагПланаПорций] = [], начало = 0, байты = 0
        func завершить(_ конец: Int) {
            if начало < конец { шаги.append(.init(начало: начало, конец: конец, байты: байты, допускаетОбход: true)) }
            начало = конец; байты = 0
        }
        for (номер, документ) in документы.enumerated() {
            if документ.размер > байтовВПорции {
                завершить(номер)
                шаги.append(.init(начало: номер, конец: номер + 1, байты: документ.размер, допускаетОбход: false))
                начало = номер + 1
                continue
            }
            if номер - начало >= документовВПорции || документ.размер > байтовВПорции - байты { завершить(номер) }
            байты += документ.размер
        }
        завершить(документы.count)
        return .init(шаги: шаги, входы: документы, байты: сумма,
            хэшСостава: хэш.finalize().map { String(format: "%02x", $0) }.joined(),
            опоры: .init(хэшОжидания, хэшФизическогоСнимка, хэшСобственногоИсточника, хэшКонтекста))
    }
}

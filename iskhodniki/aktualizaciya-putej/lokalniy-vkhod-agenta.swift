import Foundation
import CryptoKit
import Darwin

enum ОшибкаЛокальногоВхода: Error, CustomStringConvertible {
    case отказ(String)

    var description: String {
        switch self { case .отказ(let причина): причина }
    }
}

struct ИсточникОписанияАгента: Codable, Equatable, Sendable {
    var путь: String
    var коммит: String
    var хэшSHA256: String
}

struct ОписаниеЛокальногоВходаАгента: Codable, Equatable, Sendable {
    var схема = "fum.описание-локального-входа-агента.1"
    var версия: Int
    var логическийАдрес: String
    var путьКаталога: String
    var областьЗаписи: [String]
    var родитель: String
    var дети: [String]
    var источник: ИсточникОписанияАгента
    var источникКорневыхПравил: ИсточникОписанияАгента
}

enum ЛокальныйВходАгента {
    static func сформировать(описание: ОписаниеЛокальногоВходаАгента,
                              кореньРепозитория: URL, каталогАгента: URL) throws -> String {
        guard описание.схема == "fum.описание-локального-входа-агента.1", описание.версия == 1 else {
            throw ОшибкаЛокальногоВхода.отказ("Неизвестная или устаревшая версия описания узла")
        }
        try проверитьHex(описание.источник.коммит, длина: 40, поле: "commit источника")
        try проверитьHex(описание.источник.хэшSHA256, длина: 64, поле: "SHA-256 источника")
        guard описание.источникКорневыхПравил.путь == "AGENTS.md" else {
            throw ОшибкаЛокальногоВхода.отказ("Источник корневых правил должен быть точным AGENTS.md")
        }
        try проверитьHex(описание.источникКорневыхПравил.коммит, длина: 40, поле: "commit корневых правил")
        try проверитьHex(описание.источникКорневыхПравил.хэшSHA256, длина: 64, поле: "SHA-256 корневых правил")
        guard !описание.логическийАдрес.isEmpty, !описание.родитель.isEmpty,
              !описание.дети.contains(where: \.isEmpty), !описание.областьЗаписи.isEmpty else {
            throw ОшибкаЛокальногоВхода.отказ("Описание узла неполное")
        }
        try проверитьОтносительныйПуть(описание.путьКаталога)
        try описание.областьЗаписи.forEach { путь in
            try проверитьОтносительныйПуть(путь)
            guard путь == описание.путьКаталога || путь.hasPrefix(описание.путьКаталога + "/") else {
                throw ОшибкаЛокальногоВхода.отказ("Область записи выходит за каталог агента")
            }
        }
        try проверитьОтносительныйПуть(описание.источник.путь)

        let корень = кореньРепозитория.standardizedFileURL.resolvingSymlinksInPath()
        let каталог = каталогАгента.standardizedFileURL
        let путьКорня = корень.path.hasSuffix("/") ? корень.path : корень.path + "/"
        guard каталог.path.hasPrefix(путьКорня) else {
            throw ОшибкаЛокальногоВхода.отказ("Каталог агента вне корня checkout")
        }
        try проверитьСуществованиеПути(корень: корень, каталог: каталог)
        let файлКорневыхПравил = корень.appendingPathComponent("AGENTS.md")
        var сведения = stat()
        guard lstat(файлКорневыхПравил.path, &сведения) == 0,
              (сведения.st_mode & S_IFMT) == S_IFREG else {
            throw ОшибкаЛокальногоВхода.отказ("Корневой AGENTS.md отсутствует или не является обычным файлом")
        }
        let байтыКорневыхПравил = try Data(contentsOf: файлКорневыхПравил)
        let хэшКорневыхПравил = SHA256.hash(data: байтыКорневыхПравил)
            .map { String(format: "%02x", $0) }.joined()
        guard хэшКорневыхПравил == описание.источникКорневыхПравил.хэшSHA256 else {
            throw ОшибкаЛокальногоВхода.отказ("Хэш корневых правил не совпадает с версией описания")
        }
        let относительныйПуть = String(каталог.path.dropFirst(путьКорня.count))
        guard относительныйПуть == описание.путьКаталога else {
            throw ОшибкаЛокальногоВхода.отказ("Фактический каталог не совпадает с описанием узла")
        }
        let глубина = относительныйПуть.split(separator: "/").count
        let путьКПравилам = Array(repeating: "..", count: глубина).joined(separator: "/") + "/AGENTS.md"
        let областьЗаписи = Set(описание.областьЗаписи).map { "- `\($0)`" }.sorted().joined(separator: "\n")
        let дети = описание.дети.map { "- `\($0)`" }.sorted().joined(separator: "\n")
        return """
        # Локальный вход агента

        Логический адрес: `\(описание.логическийАдрес)`.

        ## Обязательное ядро

        Прочитай полностью корневой файл правил текущего checkout: [`AGENTS.md`](\(путьКПравилам)). Ссылка только указывает источник: Markdown-ссылка не подтверждает чтение. Затем прочитай все применимые тематические файлы маршрута, выбранного корневым маршрутизатором. При запрете Python передай ROOT препятствие маршрутизации и не подменяй её иной проверкой.

        ## Область и иерархия

        Родитель: `\(описание.родитель)`.

        Дети:
        \(дети)

        Собственная область записи:
        \(областьЗаписи)

        Чужие области и память — только для чтения. Не расширяй grant молчанием родителя; передавай открытые вопросы своему непосредственному родителю.

        ## Язык и происхождение

        Человеку и родителю отвечай по-русски кириллицей. Технические идентификаторы, команды, пути и RAW сохраняй точно.

        Описание узла: `\(описание.источник.путь)`; source commit `\(описание.источник.коммит)`; SHA-256 `\(описание.источник.хэшSHA256)`.

        Корневой источник: `AGENTS.md`; source commit `\(описание.источникКорневыхПравил.коммит)`; SHA-256 `\(описание.источникКорневыхПравил.хэшSHA256)`.

        Подтверждение чтения — только после фактического полного чтения указанной версии корневого источника. Запиши version-specific ACK в существующем Журнале своей задачи, связав логический адрес, источник, source commit, SHA-256 и факт полного чтения. Наличие локального `AGENTS.md` или его хэш сами по себе не доказывают чтение. Отдельный независимый реестр ACK не создавай.
        """ + "\n"
    }

    private static func проверитьHex(_ значение: String, длина: Int, поле: String) throws {
        guard значение.utf8.count == длина,
              значение.utf8.allSatisfy({ (48...57).contains($0) || (97...102).contains($0) }) else {
            throw ОшибкаЛокальногоВхода.отказ("Некорректный \(поле)")
        }
    }

    private static func проверитьОтносительныйПуть(_ путь: String) throws {
        let части = путь.split(separator: "/", omittingEmptySubsequences: false)
        guard !путь.isEmpty, !путь.hasPrefix("/"),
              части.allSatisfy({ !$0.isEmpty && $0 != "." && $0 != ".." }),
              !путь.unicodeScalars.contains(where: { $0.value == 0 }) else {
            throw ОшибкаЛокальногоВхода.отказ("Небезопасный относительный путь")
        }
    }

    private static func проверитьСуществованиеПути(корень: URL, каталог: URL) throws {
        var текущий = корень
        for компонент in каталог.pathComponents.dropFirst(корень.pathComponents.count) {
            текущий.appendPathComponent(компонент, isDirectory: true)
            var сведения = stat()
            guard lstat(текущий.path, &сведения) == 0,
                  (сведения.st_mode & S_IFMT) != S_IFLNK,
                  (сведения.st_mode & S_IFMT) == S_IFDIR else {
                throw ОшибкаЛокальногоВхода.отказ("Отсутствующий каталог, symlink или компонент не-каталог")
            }
        }
    }
}

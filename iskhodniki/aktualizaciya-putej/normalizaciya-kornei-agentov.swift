enum ПланировщикНормализацииКорнейАгентов {
    private struct ЗаписьПостановки: Decodable {
        let корень: String
        let адрес: String
        let память: String
        let историческая_область: String
        let область_первого_писателя: [String]
    }

    private struct ЗаписьКарты: Decodable {
        struct Поручение: Decodable {
            let корневой_uuid: String
            let писатель_uuid: String
            let ветка: String
            let область: String
        }
        struct Навигация: Decodable { let путь: String }
        let поручение: Поручение
        let навигация: [Навигация]
    }

    private struct ЗаписьДерева {
        let имя: String
        let тип: String
        let режим: String
        let объект: String
    }

    static func построить(
        _ назначение: НазначениеНормализацииКорнейАгентов
    ) async throws -> КонтрольнаяТочкаНормализацииКорнейАгентов {
        try проверитьНазначение(назначение)
        let корень = URL(fileURLWithPath: назначение.кореньРепозитория, isDirectory: true)
        let состояние = try снятьСостояниеGit(корень, назначение)
        try проверитьРеестр(корень, назначение)
        let отображение = try await ПубличныйФасадИмён.канонизировать(назначение.владение.исходныйКорень)
        guard Data(отображение.значение.utf8) == Data(назначение.владение.целевойКорень.utf8) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("имя-не-совпало-с-Names")
        }

        let планШагов = try построитьШаги(
            корень: корень,
            исходныйКорень: назначение.владение.исходныйКорень,
            целевойКорень: назначение.владение.целевойКорень,
            исходноеДерево: назначение.снимок.исходноеДерево,
            целевоеДерево: назначение.снимок.целевоеДерево)
        var шаги = планШагов.шаги
        let конечныеДокументы = try целевыеБайтыДокументов(
            корень: корень,
            назначение: назначение,
            шаги: шаги)
        let конечныеSHA = Dictionary(uniqueKeysWithValues: конечныеДокументы.map { ($0.key, хэш($0.value.байты)) })
        for документ in назначение.документыСсылок.sorted(by: { порядокПутей($0.путь, $1.путь) }) {
            guard let конечныйПуть = конечныеДокументы.first(where: { $0.value.исходныйПуть == документ.путь })?.key,
                  let конечный = конечныеДокументы[конечныйПуть],
                  let запись = try записьДерева(корень, коммит: назначение.снимок.commit, путь: документ.путь),
                  let физический = try отпечатокФайловойСистемы(корень, документ.путь) else {
                throw ОшибкаНормализацииКорнейАгентов.условие("закреплённый-документ-не-имеет-однозначного-переноса")
            }
            шаги.append(.init(
                номер: шаги.count,
                вид: .обновлениеДокумента,
                исходныйПуть: документ.путь,
                целевойПуть: конечныйПуть,
                исходныйТип: запись.тип,
                исходныйРежим: запись.режим,
                исходныйОбъект: запись.объект,
                целевойТип: "blob",
                целевойРежим: запись.режим,
                целевойОбъект: объектGit(байты: конечный.байты),
                исходныйОтпечаток: физический,
                целевойОтпечаток: nil,
                причинаКонфликта: nil))
        }
        try проверитьШагиВГраницахДопуска(шаги, назначение: назначение)
        let назначениеSHA = хэш(try каноническиеБайты(назначение))
        let operationID = сформироватьИдентификаторОперации(назначение)
        let временнаяТочка = КонтрольнаяТочкаНормализацииКорнейАгентов(
            operationID: operationID,
            назначениеSHA256: назначениеSHA,
            планSHA256: "",
            допуск: назначение.допуск,
            основа: состояние,
            шаги: шаги,
            документыСсылок: назначение.документыСсылок,
            целевыеSHA256Документов: конечныеSHA,
            конфликты: планШагов.конфликты,
            итоговыйИндексSHA256: состояние.индексSHA256)
        let планSHA = хэш(try каноническиеБайты(временнаяТочка))
        return КонтрольнаяТочкаНормализацииКорнейАгентов(
            operationID: operationID,
            назначениеSHA256: назначениеSHA,
            планSHA256: планSHA,
            допуск: назначение.допуск,
            основа: состояние,
            шаги: шаги,
            документыСсылок: назначение.документыСсылок,
            целевыеSHA256Документов: конечныеSHA,
            конфликты: планШагов.конфликты,
            итоговыйИндексSHA256: состояние.индексSHA256)
    }

    static func каноническиеБайты<T: Encodable>(_ значение: T) throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(значение)
    }

    static func хэш(_ данные: Data) -> String {
        SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
    }

    static func сформироватьИдентификаторОперации(_ назначение: НазначениеНормализацииКорнейАгентов) -> String {
        let владение = назначение.владение
        let снимок = назначение.снимок
        let допуск = назначение.допуск
        let основание = [
            владение.cellID, владение.владелец, владение.fullRef,
            владение.исходныйКорень, владение.целевойКорень,
            допуск.trustedRoot, допуск.toolsActorUUID, допуск.preparationWUUID,
            допуск.effect.rawValue,
            снимок.cellID, снимок.владелецЗапуска, снимок.fullRefЗапуска,
            снимок.commit, снимок.дерево
        ].joined(separator: "\0")
        return "fum-нормализация-корня-" + хэш(Data(основание.utf8))
    }

    static func проверитьНазначение(_ назначение: НазначениеНормализацииКорнейАгентов) throws {
        let привязка = назначение.владение
        let допуск = назначение.допуск
        let снимок = назначение.снимок
        let адресКорня = URL(fileURLWithPath: назначение.кореньРепозитория, isDirectory: true)
        guard адресКорня.path == назначение.кореньРепозитория,
              адресКорня.standardizedFileURL.path == назначение.кореньРепозитория,
              адресКорня.resolvingSymlinksInPath().path == назначение.кореньРепозитория,
              !назначение.кореньРепозитория.isEmpty,
              снимок.cellID.range(of: #"\A[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\z"#, options: .regularExpression) != nil,
              привязка.cellID.range(of: #"\A[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\z"#, options: .regularExpression) != nil,
              привязка.владелец.range(of: #"\A[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\z"#, options: .regularExpression) != nil,
              привязка.fullRef.hasPrefix("refs/heads/fum-lab/fum/"),
              снимок.fullRefЗапуска.hasPrefix("refs/heads/fum-lab/fum/"),
              снимок.commit.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil,
              снимок.дерево.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil,
              снимок.исходноеДерево.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil,
              снимок.целевоеДерево.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil,
              снимок.индексSHA256.range(of: #"\A[0-9a-f]{64}\z"#, options: .regularExpression) != nil,
              привязка.постановкаSHA256.range(of: #"\A[0-9a-f]{64}\z"#, options: .regularExpression) != nil,
              привязка.картаSHA256.range(of: #"\A[0-9a-f]{64}\z"#, options: .regularExpression) != nil,
              допуск.toolsActorUUID.range(of: #"\A[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\z"#, options: .regularExpression) != nil,
              допуск.preparationWUUID.range(of: #"\A[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}\z"#, options: .regularExpression) != nil,
              допуск.effect == .слияниеКорнейСОбновлениемЗакреплённыхДокументов else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неверные-идентификаторы-и-pins")
        }
        let документы = назначение.документыСсылок.map(\.путь)
        let закреплённыеДокументы = допуск.pinnedDocuments
        guard допуск.trustedRoot == назначение.кореньРепозитория,
              допуск.fullRef == снимок.fullRefЗапуска,
              допуск.gitAuthorIdentity == снимок.владелецЗапуска,
              допуск.baseCommit == снимок.commit,
              допуск.baseTree == снимок.дерево,
              допуск.indexSHA256 == снимок.индексSHA256,
              допуск.sourceTree == снимок.исходноеДерево,
              допуск.targetTree == снимок.целевоеДерево,
              допуск.sourceRoot == привязка.исходныйКорень,
              допуск.targetRoot == привязка.целевойКорень,
              Set(закреплённыеДокументы) == Set(документы),
              закреплённыеДокументы.count == документы.count else {
            throw ОшибкаНормализацииКорнейАгентов.условие("текущий-допуск-не-связан-с-намерением")
        }
        try ИменаПутей.проверитьПуть(привязка.исходныйКорень)
        try ИменаПутей.проверитьПуть(привязка.целевойКорень)
        guard !привязка.исходныйКорень.contains("/"),
              !привязка.целевойКорень.contains("/"),
              Data(привязка.исходныйКорень.utf8) != Data(привязка.целевойКорень.utf8),
              привязка.постановкаПуть == привязка.целевойКорень + "/postanovka.json",
              привязка.картаПуть == привязка.целевойКорень + "/karta.json",
              назначение.документыСсылок.count == 2 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неявный-корень-или-реестр")
        }
        let пути = назначение.документыСсылок.map { Data($0.путь.utf8) }
        guard Set(пути).count == пути.count,
              назначение.документыСсылок.allSatisfy({
                  $0.sha256.range(of: #"\A[0-9a-f]{64}\z"#, options: .regularExpression) != nil
                    && $0.gitОбъект.range(of: #"\A[0-9a-f]{40}\z"#, options: .regularExpression) != nil
              }),
              назначение.документыСсылок.contains(where: { $0.путь == привязка.картаПуть && $0.sha256 == привязка.картаSHA256 }),
              назначение.документыСсылок.contains(where: { $0.путь == привязка.исходныйКорень + "/README.md" }),
              Set(пути) == Set([Data(привязка.картаПуть.utf8), Data((привязка.исходныйКорень + "/README.md").utf8)]) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неприкреплённые-ссылки")
        }
    }

    static func проверитьШагиВГраницахДопуска(
        _ шаги: [ШагНормализацииКорняАгента],
        назначение: НазначениеНормализацииКорнейАгентов
    ) throws {
        let допуск = назначение.допуск
        func путьВнутри(_ путь: String, _ корень: String) -> Bool {
            Data(путь.utf8).starts(with: Data((корень + "/").utf8))
        }
        func путьДокументаПослеПереноса(_ путь: String) -> String? {
            if путьВнутри(путь, допуск.sourceRoot) {
                return допуск.targetRoot + String(путь.dropFirst(допуск.sourceRoot.count))
            }
            if путьВнутри(путь, допуск.targetRoot) { return путь }
            return nil
        }
        let парыДокументов = Set(допуск.pinnedDocuments.compactMap { путь -> String? in
            guard let целевой = путьДокументаПослеПереноса(путь) else { return nil }
            return путь + "\0" + целевой
        })
        guard парыДокументов.count == допуск.pinnedDocuments.count else {
            throw ОшибкаНормализацииКорнейАгентов.условие("закреплённый-документ-вне-области-допуска")
        }
        for шаг in шаги {
            if шаг.вид == .обновлениеДокумента {
                guard парыДокументов.contains(шаг.исходныйПуть + "\0" + шаг.целевойПуть) else {
                    throw ОшибкаНормализацииКорнейАгентов.условие("обновление-документа-вне-допуска")
                }
            } else {
                guard путьВнутри(шаг.исходныйПуть, допуск.sourceRoot),
                      путьВнутри(шаг.целевойПуть, допуск.targetRoot) else {
                    throw ОшибкаНормализацииКорнейАгентов.условие("шаг-вне-допуска-корней")
                }
            }
        }
        let обновленияДокументов = шаги.filter { $0.вид == .обновлениеДокумента }.map {
            $0.исходныйПуть + "\0" + $0.целевойПуть
        }
        guard Set(обновленияДокументов) == парыДокументов,
              обновленияДокументов.count == парыДокументов.count else {
            throw ОшибкаНормализацииКорнейАгентов.условие("неполный-набор-закреплённых-документов-в-плане")
        }
    }

    private static func проверитьРеестр(
        _ корень: URL,
        _ назначение: НазначениеНормализацииКорнейАгентов
    ) throws {
        let привязка = назначение.владение
        let постановкаДанные = try прочитатьФайл(корень, привязка.постановкаПуть, предел: 1_048_576)
        let картаДанные = try прочитатьФайл(корень, привязка.картаПуть, предел: 4_194_304)
        guard хэш(постановкаДанные) == привязка.постановкаSHA256,
              хэш(картаДанные) == привязка.картаSHA256 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-закреплённого-реестра")
        }
        let постановка = try JSONDecoder().decode(ЗаписьПостановки.self, from: постановкаДанные)
        let карта = try JSONDecoder().decode(ЗаписьКарты.self, from: картаДанные)
        guard Data(постановка.корень.utf8) == Data(привязка.cellID.utf8),
              Data(постановка.историческая_область.utf8) == Data(привязка.исходныйКорень.utf8),
              Data(постановка.память.utf8) == Data(привязка.целевойКорень.utf8),
              постановка.область_первого_писателя == [привязка.целевойКорень + "/**"],
              Data(("refs/heads/" + постановка.адрес).utf8) == Data(привязка.fullRef.utf8),
              Data(карта.поручение.корневой_uuid.utf8) == Data(привязка.cellID.utf8),
              Data(карта.поручение.писатель_uuid.utf8) == Data(привязка.владелец.utf8),
              Data(карта.поручение.ветка.utf8) == Data(привязка.fullRef.utf8),
              Data(карта.поручение.область.utf8) == Data((привязка.целевойКорень + "/**").utf8),
              карта.навигация.contains(where: { $0.путь == привязка.исходныйКорень + "/README.md" }),
              карта.навигация.contains(where: { $0.путь == привязка.исходныйКорень + "/URL/" }) else {
            throw ОшибкаНормализацииКорнейАгентов.условие("реестр-не-подтверждает-корень-и-владельца")
        }
    }

    private static func снятьСостояниеGit(
        _ корень: URL,
        _ назначение: НазначениеНормализацииКорнейАгентов
    ) throws -> СнимокНормализацииКорнейАгентов {
        let снимок = назначение.снимок
        func текст(_ аргументы: [String]) throws -> String {
            let байты = try ЧитательПутей.гит(корень, ["--no-replace-objects", "--literal-pathspecs"] + аргументы).0
            guard let значение = String(data: байты, encoding: .utf8) else {
                throw ОшибкаНормализацииКорнейАгентов.условие("не-UTF8-ответ-Git")
            }
            return значение.trimmingCharacters(in: .newlines)
        }
        guard try текст(["rev-parse", "--show-toplevel"]) == корень.path,
              try текст(["rev-parse", "HEAD"]) == снимок.commit,
              try текст(["rev-parse", "HEAD^{tree}"]) == снимок.дерево,
              try текст(["symbolic-ref", "HEAD"]) == снимок.fullRefЗапуска else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-корня-ветки-или-клетки")
        }
        let имя = try текст(["config", "--get", "user.name"])
        let почта = try текст(["config", "--get", "user.email"])
        guard "\(имя) <\(почта)>" == снимок.владелецЗапуска else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-автора")
        }
        let статус = try ЧитательПутей.гит(
            корень,
            ["--no-replace-objects", "--literal-pathspecs", "status", "--porcelain=v2", "-z", "--untracked-files=all", "--ignored=matching", "--",
             назначение.владение.исходныйКорень, назначение.владение.целевойКорень]).0
        guard статус.isEmpty else {
            throw ОшибкаНормализацииКорнейАгентов.условие("грязные-или-неучтённые-корни")
        }
        let индекс = try ЧитательПутей.гит(
            корень,
            ["--no-replace-objects", "--literal-pathspecs", "ls-files", "--stage", "-z", "--",
             назначение.владение.исходныйКорень, назначение.владение.целевойКорень]).0
        for документ in назначение.документыСсылок {
            let запись = try ЧитательПутей.гит(корень, ["--no-replace-objects", "--literal-pathspecs", "ls-tree", "-z", снимок.commit, "--", документ.путь]).0
            guard let часть = запись.split(separator: 0).first,
                  let таб = часть.firstIndex(of: 9),
                  let заголовок = String(data: Data(часть[..<таб]), encoding: .utf8),
                  String(заголовок.split(separator: " ").last ?? "") == документ.gitОбъект else {
                throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-Git-объекта-документа: " + документ.путь)
            }
        }
        guard хэш(индекс) == снимок.индексSHA256,
              try текст(["rev-parse", "HEAD:" + назначение.владение.исходныйКорень]) == снимок.исходноеДерево,
              try текст(["rev-parse", "HEAD:" + назначение.владение.целевойКорень]) == снимок.целевоеДерево else {
            throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-индекса-или-деревьев")
        }
        return снимок
    }

    private static func построитьШаги(
        корень: URL,
        исходныйКорень: String,
        целевойКорень: String,
        исходноеДерево: String,
        целевоеДерево: String
    ) throws -> (шаги: [ШагНормализацииКорняАгента], конфликты: [ЗаписьКонфликтаНормализацииКорнейАгентов]) {
        var шаги: [ШагНормализацииКорняАгента] = []
        var конфликты: [ЗаписьКонфликтаНормализацииКорнейАгентов] = []
        func дети(_ дерево: String) throws -> [ЗаписьДерева] {
            let данные = try ЧитательПутей.гит(корень, ["--no-replace-objects", "--literal-pathspecs", "ls-tree", "-z", дерево]).0
            return try данные.split(separator: 0).map { запись in
                guard let табуляция = запись.firstIndex(of: 9),
                      let заголовок = String(data: Data(запись[..<табуляция]), encoding: .utf8),
                      let имя = String(data: Data(запись[запись.index(after: табуляция)...]), encoding: .utf8) else {
                    throw ОшибкаНормализацииКорнейАгентов.условие("повреждённая-запись-дерева")
                }
                let поля = заголовок.split(separator: " ")
                guard поля.count == 3 else {
                    throw ОшибкаНормализацииКорнейАгентов.условие("повреждённый-заголовок-дерева")
                }
                try ИменаПутей.проверитьПуть(имя)
                guard !имя.contains("/") else {
                    throw ОшибкаНормализацииКорнейАгентов.условие("не-компонент-дочернего-дерева")
                }
                return ЗаписьДерева(
                    имя: имя,
                    тип: String(поля[1]),
                    режим: String(поля[0]),
                    объект: String(поля[2]))
            }
        }
        func проверитьДеревоБезСимволическихСсылок(
            _ дерево: String,
            посещённые: inout Set<String>
        ) throws {
            guard посещённые.insert(дерево).inserted else { return }
            for элемент in try дети(дерево) {
                guard элемент.режим != "120000" else {
                    throw ОшибкаНормализацииКорнейАгентов.условие("вложенная-символическая-ссылка-не-переносится")
                }
                if элемент.тип == "tree" {
                    try проверитьДеревоБезСимволическихСсылок(элемент.объект, посещённые: &посещённые)
                }
            }
        }
        func отпечаток(_ путь: String) throws -> ОтпечатокФайловойСистемыНормализации? {
            try СистемаФайловНормализации.отпечаток(корень: корень, путь: путь)
        }
        func рекурсивно(
            исходноеДерево: String,
            целевоеДерево: String,
            исходныйПуть: String,
            целевойПуть: String
        ) throws {
            let исходныеДети = try дети(исходноеДерево).sorted { порядокПутей($0.имя, $1.имя) }
            let целевыеДети = try дети(целевоеДерево).sorted { порядокПутей($0.имя, $1.имя) }
            let целевыеПоТочномуИмени = Dictionary(uniqueKeysWithValues: целевыеДети.map { ($0.имя, $0) })
            let целевыеПоАлиасу = Dictionary(grouping: целевыеДети, by: { ИменаПутей.ключКоллизии($0.имя) })
            let исходныеПоАлиасу = Dictionary(grouping: исходныеДети, by: { ИменаПутей.ключКоллизии($0.имя) })
            var обработанныеАлиасы: Set<Data> = []
            for элемент in исходныеДети {
                let исходный = исходныйПуть + "/" + элемент.имя
                let целевой = целевойПуть + "/" + элемент.имя
                let ключАлиаса = ИменаПутей.ключКоллизии(элемент.имя)
                if let группа = исходныеПоАлиасу[ключАлиаса], группа.count > 1 {
                    guard обработанныеАлиасы.insert(ключАлиаса).inserted else { continue }
                    let версии = группа.map { узел in
                        ЗаписьКонфликтаНормализацииКорнейАгентов.Версия(
                            путь: исходныйПуть + "/" + узел.имя,
                            тип: узел.тип, режим: узел.режим, gitОбъект: узел.объект)
                    }
                    конфликты.append(.init(
                        целевойПуть: целевой,
                        версии: версии.sorted { порядокПутей($0.путь, $1.путь) },
                        причина: "алиас-источников-регистра-или-Unicode"))
                    guard let физическийИсходный = try отпечаток(исходный) else {
                        throw ОшибкаНормализацииКорнейАгентов.условие("нет-физического-исходного-алиаса")
                    }
                    шаги.append(.init(
                        номер: шаги.count, вид: .конфликтСохранён,
                        исходныйПуть: исходный, целевойПуть: целевой,
                        исходныйТип: элемент.тип, исходныйРежим: элемент.режим, исходныйОбъект: элемент.объект,
                        целевойТип: nil, целевойРежим: nil, целевойОбъект: nil,
                        исходныйОтпечаток: физическийИсходный, целевойОтпечаток: nil,
                        причинаКонфликта: "алиас-источников-регистра-или-Unicode"))
                    continue
                }
                let физическийИсходный = try отпечаток(исходный)
                guard let физическийИсходный else {
                    throw ОшибкаНормализацииКорнейАгентов.условие("нет-физического-исходного-узла: " + исходный)
                }
                if let точнаяЦель = целевыеПоТочномуИмени[элемент.имя] {
                    let физическаяЦель = try отпечаток(целевой)
                    guard let физическаяЦель else {
                        throw ОшибкаНормализацииКорнейАгентов.условие("нет-физического-целевого-узла: " + целевой)
                    }
                    if элемент.тип == "tree", точнаяЦель.тип == "tree" {
                        if элемент.объект == точнаяЦель.объект {
                            шаги.append(.init(
                                номер: шаги.count, вид: .удалениеДубликатаКаталога,
                                исходныйПуть: исходный, целевойПуть: целевой,
                                исходныйТип: элемент.тип, исходныйРежим: элемент.режим, исходныйОбъект: элемент.объект,
                                целевойТип: точнаяЦель.тип, целевойРежим: точнаяЦель.режим, целевойОбъект: точнаяЦель.объект,
                                исходныйОтпечаток: физическийИсходный, целевойОтпечаток: физическаяЦель,
                                причинаКонфликта: nil))
                        } else {
                            try рекурсивно(
                                исходноеДерево: элемент.объект, целевоеДерево: точнаяЦель.объект,
                                исходныйПуть: исходный, целевойПуть: целевой)
                        }
                    } else if элемент.тип == "blob", точнаяЦель.тип == "blob",
                              элемент.режим == точнаяЦель.режим, элемент.объект == точнаяЦель.объект {
                        шаги.append(.init(
                            номер: шаги.count, вид: .удалениеДубликатаФайла,
                            исходныйПуть: исходный, целевойПуть: целевой,
                            исходныйТип: элемент.тип, исходныйРежим: элемент.режим, исходныйОбъект: элемент.объект,
                            целевойТип: точнаяЦель.тип, целевойРежим: точнаяЦель.режим, целевойОбъект: точнаяЦель.объект,
                            исходныйОтпечаток: физическийИсходный, целевойОтпечаток: физическаяЦель,
                            причинаКонфликта: nil))
                    } else {
                        добавитьКонфликт(
                            исходныйПуть: исходный, целевойПуть: целевой,
                            исходный: элемент, целевой: точнаяЦель,
                            исходныйОтпечаток: физическийИсходный, целевойОтпечаток: физическаяЦель,
                            причина: "разные-версии-или-типы")
                    }
                } else if let алиасы = целевыеПоАлиасу[ключАлиаса], !алиасы.isEmpty {
                    let версии = [ЗаписьКонфликтаНормализацииКорнейАгентов.Версия(
                        путь: исходный, тип: элемент.тип, режим: элемент.режим, gitОбъект: элемент.объект)]
                        + алиасы.map { узел in
                            ЗаписьКонфликтаНормализацииКорнейАгентов.Версия(
                                путь: целевойПуть + "/" + узел.имя,
                                тип: узел.тип, режим: узел.режим, gitОбъект: узел.объект)
                        }
                    let путьАлиаса = целевойПуть + "/" + алиасы[0].имя
                    guard let физическаяЦель = try отпечаток(путьАлиаса) else {
                        throw ОшибкаНормализацииКорнейАгентов.условие("нет-физического-алиаса-назначения")
                    }
                    добавитьКонфликт(
                        исходныйПуть: исходный, целевойПуть: путьАлиаса,
                        исходный: элемент, целевой: алиасы[0],
                        исходныйОтпечаток: физическийИсходный, целевойОтпечаток: физическаяЦель,
                        версии: версии,
                        причина: "алиас-регистра-или-Unicode")
                } else if элемент.тип == "commit" {
                    шаги.append(.init(
                        номер: шаги.count, вид: .конфликтСохранён,
                        исходныйПуть: исходный, целевойПуть: целевой,
                        исходныйТип: элемент.тип, исходныйРежим: элемент.режим, исходныйОбъект: элемент.объект,
                        целевойТип: nil, целевойРежим: nil, целевойОбъект: nil,
                        исходныйОтпечаток: физическийИсходный, целевойОтпечаток: nil,
                        причинаКонфликта: "внешняя-Git-граница")
                    конфликты.append(.init(
                        целевойПуть: целевой,
                        версии: [.init(путь: исходный, тип: элемент.тип, режим: элемент.режим, gitОбъект: элемент.объект)],
                        причина: "внешняя-Git-граница"))
                } else {
                    шаги.append(.init(
                        номер: шаги.count,
                        вид: элемент.тип == "tree" ? .переносКаталога : .переносФайла,
                        исходныйПуть: исходный, целевойПуть: целевой,
                        исходныйТип: элемент.тип, исходныйРежим: элемент.режим, исходныйОбъект: элемент.объект,
                        целевойТип: nil, целевойРежим: nil, целевойОбъект: nil,
                        исходныйОтпечаток: физическийИсходный, целевойОтпечаток: nil,
                        причинаКонфликта: nil))
                }
            }
        }
        func добавитьКонфликт(
            исходныйПуть: String,
            целевойПуть: String,
            исходный: ЗаписьДерева,
            целевой: ЗаписьДерева,
            исходныйОтпечаток: ОтпечатокФайловойСистемыНормализации,
            целевойОтпечаток: ОтпечатокФайловойСистемыНормализации,
            версии: [ЗаписьКонфликтаНормализацииКорнейАгентов.Версия]? = nil,
            причина: String
        ) {
            шаги.append(.init(
                номер: шаги.count, вид: .конфликтСохранён,
                исходныйПуть: исходныйПуть, целевойПуть: целевойПуть,
                исходныйТип: исходный.тип, исходныйРежим: исходный.режим, исходныйОбъект: исходный.объект,
                целевойТип: целевой.тип, целевойРежим: целевой.режим, целевойОбъект: целевой.объект,
                исходныйОтпечаток: исходныйОтпечаток, целевойОтпечаток: целевойОтпечаток,
                причинаКонфликта: причина))
            конфликты.append(.init(
                целевойПуть: целевойПуть,
                версии: (версии ?? [
                    .init(путь: исходныйПуть, тип: исходный.тип, режим: исходный.режим, gitОбъект: исходный.объект),
                    .init(путь: целевойПуть, тип: целевой.тип, режим: целевой.режим, gitОбъект: целевой.объект)
                ]).sorted { порядокПутей($0.путь, $1.путь) },
                причина: причина))
        }
        var посещённыеДеревья: Set<String> = []
        try проверитьДеревоБезСимволическихСсылок(исходноеДерево, посещённые: &посещённыеДеревья)
        try проверитьДеревоБезСимволическихСсылок(целевоеДерево, посещённые: &посещённыеДеревья)
        try рекурсивно(
            исходноеДерево: исходноеДерево, целевоеДерево: целевоеДерево,
            исходныйПуть: исходныйКорень, целевойПуть: целевойКорень)
        let перенумерованные: [ШагНормализацииКорняАгента] = шаги.enumerated().map { номер, шаг in
            .init(
                номер: номер, вид: шаг.вид, исходныйПуть: шаг.исходныйПуть, целевойПуть: шаг.целевойПуть,
                исходныйТип: шаг.исходныйТип, исходныйРежим: шаг.исходныйРежим, исходныйОбъект: шаг.исходныйОбъект,
                целевойТип: шаг.целевойТип, целевойРежим: шаг.целевойРежим, целевойОбъект: шаг.целевойОбъект,
                исходныйОтпечаток: шаг.исходныйОтпечаток, целевойОтпечаток: шаг.целевойОтпечаток,
                причинаКонфликта: шаг.причинаКонфликта)
        }
        return (перенумерованные, конфликты)
    }

    private static func целевыеБайтыДокументов(
        корень: URL,
        назначение: НазначениеНормализацииКорнейАгентов,
        шаги: [ШагНормализацииКорняАгента]
    ) throws -> [String: (исходныйПуть: String, байты: Data)] {
        var результаты: [String: (исходныйПуть: String, байты: Data)] = [:]
        for документ in назначение.документыСсылок {
            let данные = try прочитатьФайл(корень, документ.путь, предел: 4_194_304)
            guard хэш(данные) == документ.sha256 else {
                throw ОшибкаНормализацииКорнейАгентов.условие("дрейф-документа-ссылок: " + документ.путь)
            }
            let путьРезультата = шаги.first(where: {
                ($0.вид == .переносФайла || $0.вид == .удалениеДубликатаФайла)
                    && $0.исходныйПуть == документ.путь
            })?.целевойПуть ?? документ.путь
            guard !шаги.contains(where: { $0.вид == .конфликтСохранён && $0.исходныйПуть == документ.путь }) else {
                throw ОшибкаНормализацииКорнейАгентов.условие("закреплённый-документ-содержит-конфликт")
            }
            let обновлённые = НормализацияСсылок.переписать(данные, шаги: шаги)
            результаты[путьРезультата] = (документ.путь, обновлённые)
        }
        return результаты
    }

    private static func записьДерева(_ корень: URL, коммит: String, путь: String) throws -> ЗаписьДерева? {
        let данные = try ЧитательПутей.гит(
            корень,
            ["--no-replace-objects", "--literal-pathspecs", "ls-tree", "-z", коммит, "--", путь]).0
        guard let запись = данные.split(separator: 0).first,
              let табуляция = запись.firstIndex(of: 9),
              let заголовок = String(data: Data(запись[..<табуляция]), encoding: .utf8) else { return nil }
        let поля = заголовок.split(separator: " ")
        guard поля.count == 3 else {
            throw ОшибкаНормализацииКорнейАгентов.условие("повреждённая-запись-закреплённого-документа")
        }
        return ЗаписьДерева(имя: путь, тип: String(поля[1]), режим: String(поля[0]), объект: String(поля[2]))
    }

    private static func отпечатокФайловойСистемы(_ корень: URL, _ путь: String) throws -> ОтпечатокФайловойСистемыНормализации? {
        try СистемаФайловНормализации.отпечаток(корень: корень, путь: путь)
    }

    private static func объектGit(байты: Data) -> String {
        var объект = Data("blob \(байты.count)\0".utf8)
        объект.append(байты)
        return Insecure.SHA1.hash(data: объект).map { String(format: "%02x", $0) }.joined()
    }

    private static func прочитатьФайл(_ корень: URL, _ путь: String, предел: Int) throws -> Data {
        try СистемаФайловНормализации.прочитать(корень: корень, путь: путь, предел: предел).байты
    }

    private static func порядокПутей(_ левый: String, _ правый: String) -> Bool {
        левый.utf8.lexicographicallyPrecedes(правый.utf8)
    }

struct АвтоматСессииВнешнегоАгента {
    let задача: ИдентификаторЗадачиФУМА
    private(set) var сессия: ИдентификаторВнешнейСессии?
    private(set) var состояние: СостояниеСессииВнешнегоАгента

    init(задача: ИдентификаторЗадачиФУМА) {
        self.задача = задача
        self.сессия = nil
        self.состояние = .создано(задача)
    }

    mutating func отметитьОтправкуИнициализации(_ идентификатор: ИдентификаторВызоваВнешнегоАгента) throws {
        guard состояние == .создано(задача) else {
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        состояние = .инициализацияОтправлена(задача, идентификатор)
    }

    mutating func принятьОтветИнициализации(_ кадр: КадрВнешнегоАгента) throws {
        guard case .инициализацияОтправлена(_, let ожидаемый) = состояние else {
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        try Self.проверитьОтвет(кадр, ожидаемый: ожидаемый)
        guard let результат = кадр.объект["result"] as? [String: Any],
              let версия = результат["protocolVersion"] as? NSNumber,
              CFGetTypeID(версия) != CFBooleanGetTypeID(),
              версия.intValue == 1,
              версия.doubleValue == 1
        else {
            throw ОшибкаСессииВнешнегоАгента.неверныйОтвет
        }
        состояние = .инициализировано(задача)
    }

    mutating func отметитьОтправкуСозданияСессии(_ идентификатор: ИдентификаторВызоваВнешнегоАгента) throws {
        guard состояние == .инициализировано(задача) else {
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        состояние = .созданиеСессииОтправлено(задача, идентификатор)
    }

    mutating func принятьОтветСозданияСессии(_ кадр: КадрВнешнегоАгента) throws {
        guard case .созданиеСессииОтправлено(_, let ожидаемый) = состояние else {
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        try Self.проверитьОтвет(кадр, ожидаемый: ожидаемый)
        guard let результат = кадр.объект["result"] as? [String: Any],
              let значение = результат["sessionId"] as? String
        else {
            throw ОшибкаСессииВнешнегоАгента.неверныйОтвет
        }
        let сессия: ИдентификаторВнешнейСессии
        do {
            сессия = try ИдентификаторВнешнейСессии(значение)
        } catch {
            throw ОшибкаСессииВнешнегоАгента.неверныйОтвет
        }
        self.сессия = сессия
        состояние = .готово(задача, сессия)
    }

    mutating func отметитьОтправкуЗапроса(_ идентификатор: ИдентификаторВызоваВнешнегоАгента) throws {
        guard let сессия, состояние == .готово(задача, сессия) else {
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        состояние = .запросОтправлен(задача, сессия, идентификатор)
    }

    mutating func принятьСобытие(_ кадр: КадрВнешнегоАгента) throws -> СобытиеВнешнегоАгента? {
        guard let сессия,
              case .запросОтправлен = состояние
        else {
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        guard кадр.вид == .уведомление("session/update"),
              let параметры = кадр.объект["params"] as? [String: Any],
              let идентификаторСессии = параметры["sessionId"] as? String
        else {
            throw ОшибкаСессииВнешнегоАгента.неверноеСобытие
        }
        guard идентификаторСессии == сессия.значение else {
            throw ОшибкаСессииВнешнегоАгента.несовпадениеСессии
        }
        guard let обновление = параметры["update"] as? [String: Any],
              let вид = обновление["kind"] as? String,
              вид == "agent_message_chunk",
              обновление["content"] is String,
              Set(параметры.keys) == ["sessionId", "update"],
              Set(обновление.keys) == ["kind", "content"]
        else {
            throw ОшибкаСессииВнешнегоАгента.неверноеСобытие
        }
        return СобытиеВнешнегоАгента(
            задача: задача,
            сессия: сессия,
            вид: вид,
            содержимое: обновление["content"] as? String
        )
    }

    mutating func принятьОтветЗапроса(_ кадр: КадрВнешнегоАгента) throws {
        guard let сессия else {
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        let ожидаемый: ИдентификаторВызоваВнешнегоАгента
        switch состояние {
        case .запросОтправлен(_, _, let идентификатор), .отменаЗапрошена(_, _, let идентификатор):
            ожидаемый = идентификатор
        default:
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        try Self.проверитьОтвет(кадр, ожидаемый: ожидаемый)
        guard let результат = кадр.объект["result"] as? [String: Any],
              let причина = результат["stopReason"] as? String,
              Set(результат.keys) == ["stopReason"]
        else {
            throw ОшибкаСессииВнешнегоАгента.неверныйОтвет
        }
        switch причина {
        case "end_turn":
            состояние = .завершено(задача, сессия)
        case "cancelled":
            состояние = .отменено(задача, сессия)
        default:
            throw ОшибкаСессииВнешнегоАгента.неверныйОтвет
        }
    }

    mutating func отметитьЗакрытиеПотока() {
        guard let сессия else {
            return
        }
        switch состояние {
        case .запросОтправлен, .отменаЗапрошена:
            состояние = .неизвестныйИсход(задача, сессия)
        default:
            break
        }
    }

    mutating func запроситьОтмену() throws -> Data {
        guard let сессия,
              case .запросОтправлен(_, _, let идентификатор) = состояние
        else {
            throw ОшибкаСессииВнешнегоАгента.неожиданноеСостояние
        }
        let объект: [String: Any] = [
            "jsonrpc": "2.0",
            "method": "session/cancel",
            "params": ["sessionId": сессия.значение]
        ]
        let данные: Data
        do {
            данные = try JSONSerialization.data(withJSONObject: объект, options: [.sortedKeys])
        } catch {
            throw ОшибкаСессииВнешнегоАгента.неверноеСобытие
        }
        var кадр = данные
        кадр.append(0x0A)
        состояние = .отменаЗапрошена(задача, сессия, идентификатор)
        return кадр
    }

    private static func проверитьОтвет(
        _ кадр: КадрВнешнегоАгента,
        ожидаемый: ИдентификаторВызоваВнешнегоАгента
    ) throws {
        switch кадр.вид {
        case .ответ(let полученный):
            guard полученный == ожидаемый else {
                throw ОшибкаСессииВнешнегоАгента.несовпадениеИдентификатора
            }
        case .ошибка(let полученный):
            guard полученный == ожидаемый else {
                throw ОшибкаСессииВнешнегоАгента.несовпадениеИдентификатора
            }
            throw ОшибкаСессииВнешнегоАгента.ошибкаОтвета(кадр.исходныеБайты)
        default:
            throw ОшибкаСессииВнешнегоАгента.неверныйОтвет
        }
    }

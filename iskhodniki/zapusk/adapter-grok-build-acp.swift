struct ИдентификаторВызоваВнешнегоАгента: Equatable, Hashable {
    private enum Значение: Equatable, Hashable {
        case целое(Int64)
        case строка(String)
    }

    private let значение: Значение

    init(_ значение: Int) {
        self.значение = .целое(Int64(значение))
    }

    init(_ значение: Int64) {
        self.значение = .целое(значение)
    }

    init(_ значение: String) throws {
        try ПроверкаЗначенияВнешнегоАгента.проверитьИдентификатор(значение)
        self.значение = .строка(значение)
    }

    fileprivate init(из значение: Any) throws {
        if let строка = значение as? String {
            try self.init(строка)
            return
        }
        guard let число = значение as? NSNumber,
              CFGetTypeID(число) != CFBooleanGetTypeID(),
              число.doubleValue.isFinite,
              число.doubleValue.rounded() == число.doubleValue,
              число.doubleValue >= Double(Int64.min),
              число.doubleValue <= Double(Int64.max)
        else {
            throw ОшибкаКадраВнешнегоАгента.некорректнаяОболочка
        }
        self.init(число.int64Value)
    }
}

private enum ПроверкаЗначенияВнешнегоАгента {
    static func проверитьИдентификатор(_ значение: String) throws {
        guard !значение.isEmpty else {
            throw ОшибкаИдентификатораВнешнегоАгента.пустоеЗначение
        }
        guard значение.utf8.count <= 256,
              значение.unicodeScalars.allSatisfy({
                  !$0.properties.isWhitespace && !CharacterSet.controlCharacters.contains($0)
              })
        else {
            throw ОшибкаИдентификатораВнешнегоАгента.недопустимоеЗначение
        }
    }

    static func являетсяШестнадцатеричным(_ значение: String, длина: Int) -> Bool {
        значение.utf8.count == длина && значение.utf8.allSatisfy {
            ($0 >= 48 && $0 <= 57) || ($0 >= 97 && $0 <= 102)
        }
    }
}


    let причина: ОшибкаКадраВнешнегоАгента
    let принятыеБайты: [Data]
    let отклонённыеБайты: Data
    let непринятыеБайты: Data
}

struct ДекодерКадровВнешнегоАгента {
    private var буфер = Data()
    private let пределБайтов: Int
    var неполныйХвост: Data { буфер }

    init(пределБайтов: Int = 1_048_576) {
        self.пределБайтов = пределБайтов
    }

    mutating func принять(_ данные: Data) throws -> [КадрВнешнегоАгента] {
        guard пределБайтов > 0 else {
            throw ОшибкаКадраВнешнегоАгента.слишкомБольшойКадр
        }
        var кадры: [КадрВнешнегоАгента] = []
        var начало = данные.startIndex
        while начало < данные.endIndex {
            let граница = данные[начало...].firstIndex(of: 0x0A)
            let конец = граница ?? данные.endIndex
            let длина = данные.distance(from: начало, to: конец)
            guard длина <= пределБайтов - буфер.count else {
                throw СбойДекодированияВнешнегоАгента(
                    причина: .слишкомБольшойКадр,
                    принятыеБайты: кадры.map(\.исходныеБайты),
                    отклонённыеБайты: буфер,
                    непринятыеБайты: Data(данные[начало...])
                )
            }
            буфер.append(contentsOf: данные[начало..<конец])
            guard let граница else { break }
            let послеГраницы = данные.index(after: граница)
            do {
                let кадр = try Self.разобрать(буфер)
                кадры.append(кадр)
                буфер.removeAll(keepingCapacity: true)
            } catch let ошибка {
                var отклонённыеБайты = буфер
                отклонённыеБайты.append(0x0A)
                буфер.removeAll(keepingCapacity: false)
                throw СбойДекодированияВнешнегоАгента(
                    причина: (ошибка as? ОшибкаКадраВнешнегоАгента) ?? .некорректнаяОболочка,
                    принятыеБайты: кадры.map(\.исходныеБайты),
                    отклонённыеБайты: отклонённыеБайты,
                    непринятыеБайты: Data(данные[послеГраницы...])
                )
            }
            начало = послеГраницы
        }
        return кадры
    }

    mutating func завершить() throws -> [КадрВнешнегоАгента] {
        guard буфер.isEmpty else {
            throw ОшибкаКадраВнешнегоАгента.неполныйКадр
        }
        return []
    }

    private static func разобрать(_ строка: Data) throws -> КадрВнешнегоАгента {
        guard !строка.isEmpty else {
            throw ОшибкаКадраВнешнегоАгента.пустойКадр
        }
        guard !строка.contains(0x0D) else {
            throw ОшибкаКадраВнешнегоАгента.возвратКаретки
        }
        guard String(data: строка, encoding: .utf8) != nil else {
            throw ОшибкаКадраВнешнегоАгента.некорректнаяКодировка
        }
        let числовоеПредставлениеID = try Self.извлечьЧисловоеПредставлениеID(из: строка)

        let разобранное: Any
        do {
            разобранное = try JSONSerialization.jsonObject(with: строка)
        } catch {
            throw ОшибкаКадраВнешнегоАгента.некорректныйДокумент
        }
        guard let объект = разобранное as? [String: Any],
              объект["jsonrpc"] as? String == "2.0"
        else {
            throw ОшибкаКадраВнешнегоАгента.некорректнаяОболочка
        }

        let вид: ВидКадраВнешнегоАгента
        if let метод = объект["method"] as? String {
            guard !метод.isEmpty,
                  Set(объект.keys).isSubset(of: ["jsonrpc", "id", "method", "params"]),
                  объект["result"] == nil,
                  объект["error"] == nil
            else {
                throw ОшибкаКадраВнешнегоАгента.некорректнаяОболочка
            }
            if let значение = объект["id"] {
                вид = .запрос(
                    метод,
                    try ИдентификаторВызоваВнешнегоАгента(
                        из: значение,
                        числовоеПредставление: числовоеПредставлениеID
                    )
                )
            } else {
                вид = .уведомление(метод)
            }
        } else {
            guard let значение = объект["id"],
                  Set(объект.keys).isSubset(of: ["jsonrpc", "id", "result", "error"]),
                  (объект["result"] != nil) != (объект["error"] != nil)
            else {
                throw ОшибкаКадраВнешнегоАгента.некорректнаяОболочка
            }
            let идентификатор = try ИдентификаторВызоваВнешнегоАгента(
                из: значение,
                числовоеПредставление: числовоеПредставлениеID
            )
            вид = объект["error"] == nil ? .ответ(идентификатор) : .ошибка(идентификатор)
        }

        var исходныеБайты = строка
        исходныеБайты.append(0x0A)
        return КадрВнешнегоАгента(вид: вид, исходныеБайты: исходныеБайты, объект: объект)
    }

    private static func извлечьЧисловоеПредставлениеID(из данные: Data) throws -> String? {
        let байты = Array(данные)
        var позиция = 0

        func пропуститьПробелы() {
            while позиция < байты.count,
                  байты[позиция] == 0x20 || байты[позиция] == 0x09 || байты[позиция] == 0x0A
            {
                позиция += 1
            }
        }

        func пропуститьСтроку() -> Range<Int>? {
            guard позиция < байты.count, байты[позиция] == 0x22 else { return nil }
            let начало = позиция
            позиция += 1
            while позиция < байты.count {
                if байты[позиция] == 0x5C {
                    позиция += 2
                } else if байты[позиция] == 0x22 {
                    позиция += 1
                    return начало..<позиция
                } else {
                    позиция += 1
                }
            }
            return nil
        }

        func пропуститьЗначение() -> Range<Int>? {
            пропуститьПробелы()
            guard позиция < байты.count else { return nil }
            let начало = позиция
            if байты[позиция] == 0x22 {
                return пропуститьСтроку()
            }
            if байты[позиция] == 0x7B || байты[позиция] == 0x5B {
                var глубина = 0
                var внутриСтроки = false
                var экранирован = false
                while позиция < байты.count {
                    let байт = байты[позиция]
                    позиция += 1
                    if внутриСтроки {
                        if экранирован {
                            экранирован = false
                        } else if байт == 0x5C {
                            экранирован = true
                        } else if байт == 0x22 {
                            внутриСтроки = false
                        }
                    } else if байт == 0x22 {
                        внутриСтроки = true
                    } else if байт == 0x7B || байт == 0x5B {
                        глубина += 1
                    } else if байт == 0x7D || байт == 0x5D {
                        глубина -= 1
                        if глубина == 0 { return начало..<позиция }
                    }
                }
                return nil
            }
            while позиция < байты.count,
                  байты[позиция] != 0x2C,
                  байты[позиция] != 0x7D,
                  байты[позиция] != 0x5D,
                  байты[позиция] != 0x20,
                  байты[позиция] != 0x09,
                  байты[позиция] != 0x0A
            {
                позиция += 1
            }
            return начало..<позиция
        }

        пропуститьПробелы()
        guard позиция < байты.count, байты[позиция] == 0x7B else { return nil }
        позиция += 1
        var представление: String?
        var ключи = Set<String>()
        while позиция < байты.count {
            пропуститьПробелы()
            guard позиция < байты.count else { return nil }
            if байты[позиция] == 0x7D { break }
            guard let диапазонКлюча = пропуститьСтроку(),
                  let ключ = try? JSONSerialization.jsonObject(
                      with: Data(байты[диапазонКлюча]),
                      options: [.fragmentsAllowed]
                  ) as? String
            else { return nil }
            guard ключи.insert(ключ).inserted else {
                throw ОшибкаКадраВнешнегоАгента.некорректнаяОболочка
            }
            пропуститьПробелы()
            guard позиция < байты.count, байты[позиция] == 0x3A else { return nil }
            позиция += 1
            guard let диапазонЗначения = пропуститьЗначение() else { return nil }
            if ключ == "id",
               let значение = String(data: Data(байты[диапазонЗначения]), encoding: .utf8),
               let первый = значение.utf8.first,
               первый == 0x2D || (первый >= 0x30 && первый <= 0x39)
            {
                представление = значение
            } else if ключ == "id" {
                представление = nil
            }
            пропуститьПробелы()
            guard позиция < байты.count else { return nil }
            if байты[позиция] == 0x2C {
                позиция += 1
            } else if байты[позиция] == 0x7D {
                break
            } else {
                return nil
            }
        }
        return представление
    }
}

enum ОшибкаПолномочийВнешнегоАгента: Error, Equatable {
    case пустаяОбласть
    case недопустимыйПуть
    case недопустимаяКоманда
    case недопустимыйПредел
}

struct ПолномочияВнешнегоАгента: Equatable {
    let путиЧтения: [String]
    let путиЗаписи: [String]
    let команды: [String]
    let сетьРазрешена: Bool
    let пределСекунд: Int

    init(
        путиЧтения: [String],
        путиЗаписи: [String],
        команды: [String],
        сетьРазрешена: Bool,
        пределСекунд: Int
    ) throws {
        guard !путиЧтения.isEmpty || !путиЗаписи.isEmpty || !команды.isEmpty else {
            throw ОшибкаПолномочийВнешнегоАгента.пустаяОбласть
        }
        guard (путиЧтения + путиЗаписи).allSatisfy({
            $0.hasPrefix("/") && !$0.contains("\0") && !$0.contains("/../")
        }) else {
            throw ОшибкаПолномочийВнешнегоАгента.недопустимыйПуть
        }
        guard команды.allSatisfy({ !$0.isEmpty && !$0.contains("\0") && !$0.contains("\n") }) else {
            throw ОшибкаПолномочийВнешнегоАгента.недопустимаяКоманда
        }
        guard пределСекунд > 0 else {
            throw ОшибкаПолномочийВнешнегоАгента.недопустимыйПредел
        }
        self.путиЧтения = путиЧтения
        self.путиЗаписи = путиЗаписи
        self.команды = команды
        self.сетьРазрешена = сетьРазрешена
        self.пределСекунд = пределСекунд
    }
}


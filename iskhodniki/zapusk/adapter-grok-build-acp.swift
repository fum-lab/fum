struct ПолномочияВнешнегоАгента: Equatable {
    let путиЧтения: [String]
    let путиЗаписи: [String]
    let команды: [String]
    let сетьРазрешена: Bool
    let пределСекунд: Int

    init(
        путиЧтения: [String],
        путиЗаписи: [String],
        команды: [String],
        сетьРазрешена: Bool,
        пределСекунд: Int
    ) throws {
        guard !путиЧтения.isEmpty || !путиЗаписи.isEmpty || !команды.isEmpty else {
            throw ОшибкаПолномочийВнешнегоАгента.пустаяОбласть
        }
        guard (путиЧтения + путиЗаписи).allSatisfy({
            $0.hasPrefix("/") && !$0.contains("\0") && !$0.contains("/../")
        }) else {
            throw ОшибкаПолномочийВнешнегоАгента.недопустимыйПуть
        }
        guard команды.allSatisfy({ !$0.isEmpty && !$0.contains("\0") && !$0.contains("\n") }) else {
            throw ОшибкаПолномочийВнешнегоАгента.недопустимаяКоманда
        }
        guard пределСекунд > 0 else {
            throw ОшибкаПолномочийВнешнегоАгента.недопустимыйПредел
        }
        self.путиЧтения = путиЧтения
        self.путиЗаписи = путиЗаписи
        self.команды = команды
        self.сетьРазрешена = сетьРазрешена
        self.пределСекунд = пределСекунд
    }
}


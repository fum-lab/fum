import Foundation
import Darwin

public enum ВходКоманды: Sendable {
    case помощь
    case архив([String])
    case запуск(ПараметрыЗапуска)

    public static let справка = """
    FUMA: локальная принятая история начального запуска.
    swift run
    fuma [--хранилище <абсолютный приватный путь>] [--событие <UUID>]
         [--намерение <строка>] [--профиль]
    fuma --помощь
    fuma архив-codex импорт|восстановить|восстановить-хвост <архив> <UUID сессии> <UUID поколения> <файл>

    По умолчанию: /Users/Shared/fuma-zapusk-<UID>, новый UUID
    события и фактическое UTC-время. Это идентификатор события, а не адрес узла.
    UID берётся у текущего системного пользователя; каталог создаётся с 0700.
    HOME не используется: он сам может быть Git-репозиторием.
    Тот же --событие повторяет исходное описание и время; другое намерение
    для того же ID даёт конфликт. Writer закрывается перед читающим reopen.
    Каталог должен находиться вне Git, быть физическим, принадлежать текущему
    пользователю и иметь режим 0700. Новый каталог создаётся с этим режимом.
    Хвост, повреждение и символические компоненты не исправляются.
    Ответ JSON содержит typed состояние; код отказа процесса — 2.
    Ошибка после начала записи сохраняет неизвестный либо подтверждённый
    исход события; каталог и файл могут уже существовать. Отката и слепого
    автоматического повторения нет.
    Состояние «ожидает подключения адаптера» не означает создания worktree,
    чата, подключения SDK/auth либо восстановления всего узла.
    Профиль отделяет полезный цикл внутри процесса от запуска и сборки.
    """

    public static func разобрать(_ аргументы: [String]) throws -> ВходКоманды {
        if аргументы == ["--помощь"] { return .помощь }
        if аргументы.first == "архив-codex" { return .архив(Array(аргументы.dropFirst())) }
        var значения: [String: String] = [:]
        var профиль = false
        var номер = 0
        while номер < аргументы.count {
            let ключ = аргументы[номер]
            if ключ == "--профиль" {
                guard !профиль else { throw неверныеАргументы() }
                профиль = true
                номер += 1
                continue
            }
            guard ["--хранилище", "--событие", "--намерение"].contains(ключ),
                  значения[ключ] == nil, номер + 1 < аргументы.count,
                  !аргументы[номер + 1].hasPrefix("--") else { throw неверныеАргументы() }
            значения[ключ] = аргументы[номер + 1]
            номер += 2
        }
        if let событие = значения["--событие"] {
            guard UUID(uuidString: событие)?.uuidString.lowercased() == событие
            else { throw неверныеАргументы() }
        }
        let намерение = значения["--намерение"] ?? "открыть локальную историю"
        guard !намерение.isEmpty, намерение.utf8.count <= 4096 else { throw неверныеАргументы() }
        let путь: String
        if let выбранный = значения["--хранилище"] {
            путь = выбранный
        } else {
            путь = "/Users/Shared/fuma-zapusk-\(geteuid())"
        }
        return .запуск(ПараметрыЗапуска(хранилище: путь, событие: значения["--событие"],
            намерение: намерение, профиль: профиль))
    }

    private static func неверныеАргументы() -> ОтказЗапуска {
        ОтказЗапуска(код: .аргументы, сообщение: "Некорректные аргументы; используйте --помощь.")
    }
}

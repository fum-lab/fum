import Foundation

public protocol АдаптерПакетаПутей: Sendable {
    func построить(корень: URL, поручение: Data) async throws -> Data
    func сверить(корень: URL, план: Data, sha256: String) async throws
    func применить(корень: URL, план: Data, sha256: String) async throws -> Data
}

public struct РезультатПакетаПутей: Sendable, Equatable {
    public let код: Int32
    public let вывод: Data
    public let ошибка: Data

    public init(код: Int32, вывод: Data = Data(), ошибка: Data = Data()) {
        self.код = код
        self.вывод = вывод
        self.ошибка = ошибка
    }
}

public struct ОбработчикПакетаПутей: Sendable {
    private let адаптер: any АдаптерПакетаПутей

    public init(адаптер: some АдаптерПакетаПутей) {
        self.адаптер = адаптер
    }

    public func выполнить(_ аргументы: [String]) async -> РезультатПакетаПутей {
        let команда: КомандаПакетаПутей
        do {
            команда = try РазборПакетаПутей.разобрать(аргументы)
        } catch {
            return отказ("Некорректные аргументы пакет-путей; используйте `fuma --помощь`.\n")
        }

        switch команда {
        case .построить(let корень, let путьВхода):
            let поручение: Data
            do { поручение = try Data(contentsOf: путьВхода) }
            catch { return отказ("Не удалось прочитать входные байты поручения.\n") }
            do {
                let план = try await адаптер.построить(корень: корень, поручение: поручение)
                return РезультатПакетаПутей(код: 0, вывод: план)
            } catch {
                return отказ("Построение завершилось ошибкой адаптера.\n")
            }

        case .сверить(let корень, let путьПлана, let sha256):
            let план: Data
            do { план = try Data(contentsOf: путьПлана) }
            catch { return отказ("Не удалось прочитать байты плана.\n") }
            do {
                try await адаптер.сверить(корень: корень, план: план, sha256: sha256)
                return РезультатПакетаПутей(код: 0)
            } catch {
                return отказ("Сверка завершилась ошибкой адаптера.\n")
            }

        case .применить(let корень, let путьПлана, let sha256):
            let план: Data
            do { план = try Data(contentsOf: путьПлана) }
            catch { return отказ("Не удалось прочитать байты плана; backend не вызывался.\n") }
            let байтыКвитанции: Data
            do {
                байтыКвитанции = try await адаптер.применить(корень: корень, план: план, sha256: sha256)
            } catch {
                return отказ("Исход применения неизвестен; квитанция не получена, автоматического повтора нет.\n")
            }
            return разобрать(байтыКвитанции, sha256: sha256)
        }
    }

    private func разобрать(_ байты: Data, sha256: String) -> РезультатПакетаПутей {
        guard let квитанция = try? JSONDecoder().decode(КвитанцияПакетаПутей.self, from: байты),
              квитанция.схема == "fum.квитанция-пакета-девяти-путей.1",
              квитанция.планSHA256 == sha256,
              (0...14).contains(квитанция.подтверждённыйПрефикс),
              квитанция.наблюдённыйПрефикс.map({ (0...14).contains($0) }) ?? true,
              ["завершено", "откат-проверен", "частичный", "неизвестно"].contains(квитанция.исход)
        else {
            return невернаяКвитанция(байты)
        }

        let допустима: Bool
        switch квитанция.исход {
        case "завершено":
            допустима = квитанция.подтверждённыйПрефикс == 14
                && квитанция.наблюдённыйПрефикс == 14
                && квитанция.причина == nil
        case "откат-проверен":
            допустима = квитанция.наблюдённыйПрефикс == 0
                && квитанция.причина.map { !$0.isEmpty } == true
        case "частичный":
            if let наблюдённый = квитанция.наблюдённыйПрефикс {
                допустима = (1...13).contains(наблюдённый)
                    && наблюдённый <= квитанция.подтверждённыйПрефикс + 1
                    && квитанция.причина.map { !$0.isEmpty } == true
            } else {
                допустима = false
            }
        case "неизвестно":
            допустима = квитанция.наблюдённыйПрефикс == nil
                && квитанция.причина.map { !$0.isEmpty } == true
        default:
            допустима = false
        }
        guard допустима else { return невернаяКвитанция(байты) }

        let код: Int32 = квитанция.исход == "завершено" ? 0 : 2
        return РезультатПакетаПутей(код: код, вывод: байты)
    }

    private func невернаяКвитанция(_ байты: Data) -> РезультатПакетаПутей {
        РезультатПакетаПутей(код: 2, вывод: байты,
            ошибка: Data("Неизвестная или семантически неверная квитанция; исход не принят как успех.\n".utf8))
    }

    private func отказ(_ текст: String) -> РезультатПакетаПутей {
        РезультатПакетаПутей(код: 2, ошибка: Data(текст.utf8))
    }
}

private struct КвитанцияПакетаПутей: Decodable, Sendable {
    let схема: String
    let планSHA256: String
    let исход: String
    let подтверждённыйПрефикс: Int
    let наблюдённыйПрефикс: Int?
    let причина: String?

    enum CodingKeys: String, CodingKey {
        case схема
        case планSHA256 = "план_sha256"
        case исход
        case подтверждённыйПрефикс = "подтверждённый_префикс"
        case наблюдённыйПрефикс = "наблюдённый_префикс"
        case причина
    }
}

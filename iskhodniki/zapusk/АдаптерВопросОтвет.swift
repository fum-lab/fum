import Foundation

/// Ссылка на исходный объект с версией и хэшем именно закреплённого содержимого.
public struct ЗакреплённаяСсылка: Codable, Equatable, Sendable {
    public let адрес: String
    public let версия: String
    public let sha256: String

    public init(адрес: String, версия: String, sha256: String) {
        self.адрес = адрес
        self.версия = версия
        self.sha256 = sha256
    }
}

/// Вход конечного QA-среза: вопрос и предоставленный ответ остаются раздельными.
public struct ВходВопросОтвета: Equatable, Sendable {
    public let идентификатор: String
    public let поколение: UInt64
    public let время: String
    public let назначениеПерехода: String
    public let вопрос: String
    public let ответ: String
    public let ссылкаВопроса: ЗакреплённаяСсылка
    public let ссылкаОтвета: ЗакреплённаяСсылка
    public let состояние: СостояниеПреемника

    public init(идентификатор: String, поколение: UInt64, время: String,
                назначениеПерехода: String, вопрос: String, ответ: String,
                ссылкаВопроса: ЗакреплённаяСсылка,
                ссылкаОтвета: ЗакреплённаяСсылка,
                состояние: СостояниеПреемника) {
        self.идентификатор = идентификатор
        self.поколение = поколение
        self.время = время
        self.назначениеПерехода = назначениеПерехода
        self.вопрос = вопрос
        self.ответ = ответ
        self.ссылкаВопроса = ссылкаВопроса
        self.ссылкаОтвета = ссылкаОтвета
        self.состояние = состояние
    }
}

/// Полезная нагрузка сохраняет обе ссылки отдельно от общего списка происхождения.
public struct НагрузкаВопросОтвета: Codable, Equatable, Sendable {
    public let вопрос: String
    public let ответ: String
    public let ссылкаВопроса: ЗакреплённаяСсылка
    public let ссылкаОтвета: ЗакреплённаяСсылка

    public init(вопрос: String, ответ: String,
                ссылкаВопроса: ЗакреплённаяСсылка,
                ссылкаОтвета: ЗакреплённаяСсылка) {
        self.вопрос = вопрос
        self.ответ = ответ
        self.ссылкаВопроса = ссылкаВопроса
        self.ссылкаОтвета = ссылкаОтвета
    }
}

/// Вход типизированного требования с его единственным закреплённым источником.
public struct ВходТребования: Equatable, Sendable {
    public let идентификатор: String
    public let поколение: UInt64
    public let время: String
    public let назначениеПерехода: String
    public let текст: String
    public let ссылкаТребования: ЗакреплённаяСсылка
    public let состояние: СостояниеПреемника

    public init(идентификатор: String, поколение: UInt64, время: String,
                назначениеПерехода: String, текст: String,
                ссылкаТребования: ЗакреплённаяСсылка,
                состояние: СостояниеПреемника) {
        self.идентификатор = идентификатор
        self.поколение = поколение
        self.время = время
        self.назначениеПерехода = назначениеПерехода
        self.текст = текст
        self.ссылкаТребования = ссылкаТребования
        self.состояние = состояние
    }
}

public struct НагрузкаТребования: Codable, Equatable, Sendable {
    public let текст: String
    public let ссылкаТребования: ЗакреплённаяСсылка

    public init(текст: String, ссылкаТребования: ЗакреплённаяСсылка) {
        self.текст = текст
        self.ссылкаТребования = ссылкаТребования
    }
}

/// Преобразует конечные QA/Requirement входы в общий артефакт A12.
/// Эффект выполняет только существующее хранилище; UNKNOWN возвращается без повтора.
public struct АдаптерВопросОтвет: Sendable {
    private let хранилище: ХранилищеАртефактов

    public init(хранилище: ХранилищеАртефактов) {
        self.хранилище = хранилище
    }

    public func сохранить(_ вход: ВходВопросОтвета) throws
        -> РезультатСохраненияПреемника<НагрузкаВопросОтвета> {
        let артефакт = АртефактПреемника(
            идентификатор: вход.идентификатор,
            поколение: вход.поколение,
            вид: .вопросОтвет,
            время: вход.время,
            назначениеПерехода: вход.назначениеПерехода,
            содержимое: НагрузкаВопросОтвета(
                вопрос: вход.вопрос,
                ответ: вход.ответ,
                ссылкаВопроса: вход.ссылкаВопроса,
                ссылкаОтвета: вход.ссылкаОтвета),
            происхождение: [
                вход.ссылкаВопроса.какПроисхождение(роль: .вопрос),
                вход.ссылкаОтвета.какПроисхождение(роль: .ответ)
            ],
            состояние: вход.состояние)
        return try хранилище.сохранитьПреемника(артефакт)
    }

    public func сохранитьТребование(_ вход: ВходТребования) throws
        -> РезультатСохраненияПреемника<НагрузкаТребования> {
        let артефакт = АртефактПреемника(
            идентификатор: вход.идентификатор,
            поколение: вход.поколение,
            вид: .требование,
            время: вход.время,
            назначениеПерехода: вход.назначениеПерехода,
            содержимое: НагрузкаТребования(
                текст: вход.текст,
                ссылкаТребования: вход.ссылкаТребования),
            происхождение: [вход.ссылкаТребования.какПроисхождение(роль: .требование)],
            состояние: вход.состояние)
        return try хранилище.сохранитьПреемника(артефакт)
    }
}

private extension ЗакреплённаяСсылка {
    func какПроисхождение(роль: РольПроисхождения) -> СсылкаПроисхождения {
        СсылкаПроисхождения(
            роль: роль,
            адрес: адрес,
            закреплённаяВерсия: версия,
            sha256: sha256)
    }
}

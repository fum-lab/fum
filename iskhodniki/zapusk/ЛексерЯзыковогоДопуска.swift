import Foundation

public enum ОтказЯзыковогоДопуска: Error, Sendable {
    case незавершённыйКомментарий, незавершённаяСтрока, незавершённоеИмя
    case неподдержанныйСинтаксис(String)
}

struct ЛексемаЯзыковогоДопуска: Sendable {
    let текст: String
    let строка: Int
    let столбец: Int
    let имя: Bool
    let экранирована: Bool
}

/// Только лексический профиль; выражения интерполяций читаются тем же лексером.
struct ЛексерЯзыковогоДопуска {
    private let символы: [Unicode.Scalar]
    private var позиция = 0
    private var строка = 1
    private var столбец = 1
    private var глубинаИнтерполяций = 0
    private let профильПеревода: Bool

    init(_ текст: String, профильПеревода: Bool = false) {
        символы = Array(текст.unicodeScalars)
        self.профильПеревода = профильПеревода
    }

    mutating func прочитать() throws -> [ЛексемаЯзыковогоДопуска] {
        try прочитать(доЗакрывающейСкобки: false)
    }

    private mutating func прочитать(доЗакрывающейСкобки: Bool) throws -> [ЛексемаЯзыковогоДопуска] {
        var результат: [ЛексемаЯзыковогоДопуска] = []
        var глубинаСкобок = 0
        while позиция < символы.count {
            let текущий = символы[позиция]
            if доЗакрывающейСкобки && текущий == ")" && глубинаСкобок == 0 {
                продвинуть()
                return результат
            }
            if CharacterSet.whitespacesAndNewlines.contains(текущий) {
                продвинуть(); continue
            }
            if совпадает("//") {
                while позиция < символы.count && символы[позиция] != "\n" && символы[позиция] != "\r" { продвинуть() }
                continue
            }
            if совпадает("/*") {
                try пропуститьКомментарий(); continue
            }
            var решёток = 0
            while позиция + решёток < символы.count && символы[позиция + решёток] == "#" {
                решёток += 1
            }
            if позиция + решёток < символы.count && символы[позиция + решёток] == "\"" {
                результат += try пропуститьСтроку(решёток: решёток); continue
            }
            if текущий == "(" { глубинаСкобок += 1 }
            if текущий == ")" { глубинаСкобок -= 1 }
            let начало = позиция
            let перваяСтрока = строка
            let первыйСтолбец = столбец
            if текущий == "`" {
                продвинуть()
                let началоИмени = позиция
                while позиция < символы.count && символы[позиция] != "`"
                    && символы[позиция] != "\n" && символы[позиция] != "\r" {
                    продвинуть()
                }
                guard позиция < символы.count, символы[позиция] == "`", позиция > началоИмени else {
                    throw ОтказЯзыковогоДопуска.незавершённоеИмя
                }
                let имя = текст(началоИмени, позиция)
                продвинуть()
                результат.append(.init(текст: имя, строка: перваяСтрока,
                    столбец: первыйСтолбец, имя: true, экранирована: true))
            } else if началоИмени(текущий) {
                продвинуть()
                while позиция < символы.count && частьИмени(символы[позиция]) { продвинуть() }
                результат.append(.init(текст: текст(начало, позиция), строка: перваяСтрока,
                    столбец: первыйСтолбец, имя: true, экранирована: false))
            } else {
                if текущий.value >= 0x80 {
                    throw ОтказЯзыковогоДопуска.неподдержанныйСинтаксис(
                        "Unicode scalar U+" + String(текущий.value, radix: 16))
                }
                if текущий == "/" {
                    throw ОтказЯзыковогоДопуска.неподдержанныйСинтаксис("slash/regex")
                }
                продвинуть()
                результат.append(.init(текст: String(текущий), строка: перваяСтрока,
                    столбец: первыйСтолбец, имя: false, экранирована: false))
            }
        }
        if доЗакрывающейСкобки { throw ОтказЯзыковогоДопуска.незавершённаяСтрока }
        return результат
    }

    private func началоИмени(_ символ: Unicode.Scalar) -> Bool {
        символ == "_" || CharacterSet.letters.contains(символ)
    }

    private func частьИмени(_ символ: Unicode.Scalar) -> Bool {
        началоИмени(символ) || CharacterSet.decimalDigits.contains(символ)
            || CharacterSet.nonBaseCharacters.contains(символ)
    }

    private func текст(_ начало: Int, _ конец: Int) -> String {
        String(String.UnicodeScalarView(символы[начало..<конец]))
    }

    private func совпадает(_ образец: String) -> Bool {
        let искомые = Array(образец.unicodeScalars)
        guard позиция + искомые.count <= символы.count else { return false }
        return символы[позиция..<(позиция + искомые.count)].elementsEqual(искомые)
    }

    private mutating func продвинуть(_ число: Int = 1) {
        for _ in 0..<число {
            if символы[позиция] == "\r" { строка += 1; столбец = 1 }
            else if символы[позиция] == "\n" {
                if позиция == 0 || символы[позиция - 1] != "\r" { строка += 1 }
                столбец = 1
            }
            else { столбец += 1 }
            позиция += 1
        }
    }

    private mutating func пропуститьКомментарий() throws {
        продвинуть(2)
        var глубина = 1
        while позиция < символы.count {
            if совпадает("/*") { глубина += 1; продвинуть(2) }
            else if совпадает("*/") {
                глубина -= 1; продвинуть(2)
                if глубина == 0 { return }
            } else { продвинуть() }
        }
        throw ОтказЯзыковогоДопуска.незавершённыйКомментарий
    }

    private mutating func пропуститьСтроку(решёток: Int) throws -> [ЛексемаЯзыковогоДопуска] {
        if профильПеревода && глубинаИнтерполяций > 0 {
            throw ОтказЯзыковогоДопуска.неподдержанныйСинтаксис("вложенная строка в переводе")
        }
        var выражения: [ЛексемаЯзыковогоДопуска] = []
        продвинуть(решёток)
        let кавычки = совпадает("\"\"\"") ? "\"\"\"" : "\""
        if профильПеревода && (решёток > 0 || кавычки.count > 1) {
            throw ОтказЯзыковогоДопуска.неподдержанныйСинтаксис("raw/multiline в переводе")
        }
        продвинуть(кавычки.count)
        let конец = кавычки + String(repeating: "#", count: решёток)
        let экранирование = "\\" + String(repeating: "#", count: решёток)
        while позиция < символы.count {
            if кавычки == "\"", символы[позиция] == "\n" || символы[позиция] == "\r" {
                throw ОтказЯзыковогоДопуска.незавершённаяСтрока
            }
            if совпадает(конец) { продвинуть(конец.count); return выражения }
            if совпадает(экранирование) {
                продвинуть(экранирование.count)
                guard позиция < символы.count else { break }
                if кавычки == "\"", символы[позиция] == "\n" || символы[позиция] == "\r" {
                    throw ОтказЯзыковогоДопуска.незавершённаяСтрока
                }
                if символы[позиция] == "(" {
                    guard глубинаИнтерполяций < 64 else {
                        throw ОтказЯзыковогоДопуска.неподдержанныйСинтаксис("глубина интерполяций")
                    }
                    продвинуть()
                    глубинаИнтерполяций += 1
                    let вложенные = try прочитать(доЗакрывающейСкобки: true)
                    if профильПеревода {
                        guard простаяИнтерполяция(вложенные) else {
                            throw ОтказЯзыковогоДопуска.неподдержанныйСинтаксис("сложная интерполяция в переводе")
                        }
                    }
                    выражения += вложенные
                    глубинаИнтерполяций -= 1
                    continue
                }
                продвинуть()
            } else { продвинуть() }
        }
        throw ОтказЯзыковогоДопуска.незавершённаяСтрока
    }

    private func простаяИнтерполяция(_ лексемы: [ЛексемаЯзыковогоДопуска]) -> Bool {
        guard let первая = лексемы.first else { return false }
        var позиция = 1
        if !первая.имя {
            guard первая.текст == "$" else { return false }
            while позиция < лексемы.count, лексемы[позиция].текст.utf8.count == 1,
                  let цифра = лексемы[позиция].текст.utf8.first, цифра >= 48 && цифра <= 57 {
                позиция += 1
            }
            guard позиция > 1 else { return false }
        }
        while позиция < лексемы.count {
            guard позиция + 1 < лексемы.count, лексемы[позиция].текст == ".",
                  лексемы[позиция + 1].имя else { return false }
            позиция += 2
        }
        return true
    }
}

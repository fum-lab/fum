struct ЗакреплённаяПолитикаЯзыка {
    let снимки: [String: String]
    let путьИсключений: String?
    let первичнаяОснова: String?

    init(снимки: [String: String], путьИсключений: String?, первичнаяОснова: String? = nil) {
        self.снимки = снимки
        self.путьИсключений = путьИсключений
        self.первичнаяОснова = первичнаяОснова
    }

    static let принятая = Self(снимки: [
        "Инструменты/fum-perevod-obyyavlenij-koda-na-russkij-yazyik/остаток-объявлений-кода.json":
            "632cdfe1e2d3fde8f0e97b3bded9642e0b6a054b6041445c217538816be3078f",
        "Инструменты/fum-perevod-obyyavlenij-koda-na-russkij-yazyik/аббревиатуры-контекста.json":
            "2113fbfbbb071d248bc2c686f9a85b904086788fdde68ffa3d92ab73a1a34349",
        "iskhodniki/zapusk/ВнешниеИмена.json": "8a3e07e3263660af71ab3312787764da03562c423f306f405895c01b2615aa8e",
    ], путьИсключений: "Инструменты/fum-perevod-obyyavlenij-koda-na-russkij-yazyik/аббревиатуры-контекста.json",
        первичнаяОснова: "6c09209ee3e6fb5e3dbb111eb5f41bc488d14bf6")
}

public struct РезультатЯзыковогоИндекса: Encodable, Sendable {
    public let основа: String
    public let хэшИндекса: String
    public let провереноФайлов: Int
    public let нарушения: [НарушениеЯзыковогоДопуска]
    public let профиль = "объявления-swift-дельта-1"
    public let историческийОхват = "46387 объявлений не пересчитаны; Python, Mermaid и встроенный код не проверены"
}

public enum ПроверкаЯзыковогоИндекса {
    public static func проверить(корень: String) throws -> РезультатЯзыковогоИндекса {
        try проверить(корень: корень, политика: .принятая)
    }

    static func проверить(корень: String, политика: ЗакреплённаяПолитикаЯзыка,
        среда: [String: String] = ProcessInfo.processInfo.environment) throws -> РезультатЯзыковогоИндекса {
        let физический = try ЧитательГитЯзыка.физическийПуть(корень)
        guard корень.hasPrefix("/"), физический.utf8.elementsEqual(корень.utf8) else {
            throw ОтказЧитателяЯзыка.путь("Аргумент корня отличается от разрешённого физического пути: " + корень + " → " + физический)
        }
        let гит = ЧитательГитЯзыка(корень: корень, среда: среда)
        let кореньГит = try гит.строка(["rev-parse", "--show-toplevel"])
        guard кореньГит.utf8.elementsEqual(корень.utf8) else {
            throw ОтказЧитателяЯзыка.путь("Корень Git отличается от входа: " + кореньГит + " ≠ " + корень)
        }
        guard try гит.выполнить(["ls-files", "--unmerged", "-z"]).isEmpty else {
            throw ОтказЧитателяЯзыка.формат
        }
        let основа = try гит.строка(["rev-parse", "--verify", "HEAD^{commit}"])
        let путьИндекса = try гит.строка(["rev-parse", "--path-format=absolute", "--git-path", "index"])
        let индекс = try Data(contentsOf: URL(fileURLWithPath: путьИндекса))
        guard индекс.count <= 33_554_432 else { throw ОтказЧитателяЯзыка.предел }
        let дельта = try гит.дельта(основа)
        var данныеПолитики: [String: Data] = [:]
        for (путь, ожидаемый) in политика.снимки {
            let текущие = try гит.байтыОбъекта(гит.объектИндекса(путь))
            guard ЧитательГитЯзыка.вычислитьХэш(текущие) == ожидаемый else { throw ОтказЧитателяЯзыка.политика }
            let прежняяЗапись = try гит.выполнить(["ls-tree", "-z", основа, "--", путь])
            if прежняяЗапись.isEmpty {
                guard основа == политика.первичнаяОснова, путь == "iskhodniki/zapusk/ВнешниеИмена.json" else {
                    throw ОтказЧитателяЯзыка.политика
                }
            } else {
                let прежние = try гит.байтыОбъекта(основа + ":" + путь)
                guard текущие == прежние else { throw ОтказЧитателяЯзыка.политика }
            }
            данныеПолитики[путь] = текущие
        }
        let исключения = try ИсключенияЯзыковогоДопуска.изПолитики(политика,
            данные: данныеПолитики, гит: гит)
        var нарушения: [НарушениеЯзыковогоДопуска] = []
        var проверено = 0
        for изменение in try ЧитательГитЯзыка.изменения(дельта) {
            guard изменение.путь.hasSuffix(".swift"), !изменение.путь.hasPrefix("Proyekcii/"),
                  изменение.статус != "D" else { continue }
            guard ["100644", "100755"].contains(изменение.режим), ["A", "M"].contains(изменение.статус) else {
                throw ОтказЧитателяЯзыка.формат
            }
            let данные = try гит.байтыОбъекта(изменение.новыйОбъект)
            guard let текст = String(data: данные, encoding: .utf8) else { throw ОтказЧитателяЯзыка.формат }
            let всегоСтрок = данные.filter { $0 == 10 }.count + 1
            let добавленные: Set<Int>
            if изменение.статус == "A" { добавленные = Set(1...всегоСтрок) }
            else {
                let патч = try гит.выполнить(["diff", "--text", "--no-color", "--no-ext-diff", "--no-textconv",
                    "--no-indent-heuristic", "--diff-algorithm=myers", "--unified=0", "--inter-hunk-context=0",
                    "--output-indicator-new=+", "--output-indicator-old=-", "--output-indicator-context= ",
                    изменение.старыйОбъект, изменение.новыйОбъект])
                добавленные = try ИзменённыеСтроки.прочитать(патч, всегоСтрок: всегоСтрок)
            }
            // Неподдержанный синтаксис всего изменяемого файла закрывает допуск консервативно.
            let найденные: [НарушениеЯзыковогоДопуска]
            do {
                найденные = try ПроверкаЯзыкаСвифта.проверить(текст: текст, путь: изменение.путь,
                                                          исключения: исключения)
            } catch let ошибка as ОтказЯзыковогоДопуска {
                throw ОтказЯзыковогоДопуска.неподдержанныйСинтаксис(изменение.путь + ": " + String(describing: ошибка))
            }
            let соответствие = ИзменённыеСтроки.строкиГит(данные)
            нарушения += найденные.filter { нарушение in
                (нарушение.начальнаяСтрока...нарушение.строка).contains { строка in
                    строка > 0 && строка <= соответствие.count && добавленные.contains(соответствие[строка - 1])
                }
            }
            проверено += 1
        }
        guard индекс == (try Data(contentsOf: URL(fileURLWithPath: путьИндекса))),
              основа == (try гит.строка(["rev-parse", "--verify", "HEAD^{commit}"])),
              дельта == (try гит.дельта(основа)) else { throw ОтказЧитателяЯзыка.дрейф }
        return РезультатЯзыковогоИндекса(основа: основа, хэшИндекса: ЧитательГитЯзыка.вычислитьХэш(индекс),
            провереноФайлов: проверено, нарушения: нарушения)
    }
}

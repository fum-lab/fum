import Foundation

enum КонтекстВнешнихИмён {
    private struct Контекст: Decodable {
        let схема: String
        let путь: String
        let владелец: String
        let протокол: String
        let сигнатуры: [String]
        let хэшПолногоИсходника: String
        let источник: ИсточникВнешнегоКонтракта
        let исключения: [Запись]
    }
    private struct Запись: Decodable {
        let вид: String
        let имя: String
        let строка: Int
        let столбец: Int
    }

    static func получить(текст: String, путь: String) throws -> [ИсключениеЯзыковогоДопуска] {
        guard let адрес = Bundle.module.url(forResource: "ВнешниеИмена", withExtension: "json") else {
            throw ОтказЧитателяЯзыка.политика
        }
        let данные = try Data(contentsOf: адрес)
        guard ЧитательГитЯзыка.вычислитьХэш(данные) == "8a3e07e3263660af71ab3312787764da03562c423f306f405895c01b2615aa8e" else {
            throw ОтказЧитателяЯзыка.политика
        }
        let контекст = try JSONDecoder().decode(Контекст.self, from: данные)
        guard контекст.схема == "fum.конечный-контекст-внешних-имён.1",
              контекст.исключения.count == 3 else { throw ОтказЧитателяЯзыка.политика }
        guard контекст.путь.utf8.elementsEqual(путь.utf8) else { return [] }
        guard контекст.хэшПолногоИсходника == ЧитательГитЯзыка.вычислитьХэш(Data(текст.utf8)) else {
            throw ОтказЧитателяЯзыка.политика
        }
        // Хэш связывает весь файл, владельца, протокол, полные сигнатуры и положения токенов.
        // Изменение любого байта снимает разрешения; произвольный witness не выводится.
        return контекст.исключения.map {
            .init(путь: путь, вид: $0.вид, имя: $0.имя,
                причина: контекст.владелец + ": " + контекст.протокол + ": " + контекст.сигнатуры.joined(separator: "; "),
                источник: контекст.источник.адрес + " sha256:" + контекст.источник.хэш,
                строка: $0.строка, столбец: $0.столбец)
        }
    }
}

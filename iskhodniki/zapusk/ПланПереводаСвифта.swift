struct ПривязкаПереводаСвифта: Codable, Sendable {
    let идентификатор: String
    let староеИмя: String
    let новоеИмя: String
    let объявление: Int?
    let употребления: [Int]
}

struct ФайлКартыСвифта: Codable, Sendable {
    let путь: String
    let исходныйХэш: String
    let привязки: [ПривязкаПереводаСвифта]
    var конецПрофиля: Int? = nil
}

struct КартаПереводаСвифта: Codable, Sendable {
    let схема: String
    let файлы: [ФайлКартыСвифта]
}

struct ЗаменаПереводаСвифта: Codable, Sendable {
    let привязка: String
    let объявление: Bool
    let начало: Int
    let конец: Int
    let староеИмя: String
    let новоеИмя: String
}

struct ПланФайлаСвифта: Codable, Sendable {
    let путь: String
    let исходныйХэш: String
    let будущийХэш: String
    let хэшНеизменныхПромежутков: String
    let будущиеБайты: Data
    let замены: [ЗаменаПереводаСвифта]
    var конецПрофиля: Int? = nil
}

struct ПланПереводаСвифта: Codable, Sendable {
    let схема: String
    let хэшКарты: String
    let файлы: [ПланФайлаСвифта]
}

enum ОтказПереводаСвифта: Error { case вход, путь, хэш, позиция, объявление, коллизия, профиль }

struct ПозицияПереводаСвифта: Codable, Sendable {
    let текст: String
    let начало: Int
    let конец: Int
    let строка: Int
    let столбец: Int
    let экранирована: Bool
    let объявление: Bool
}

struct ЛексемыПереводаСвифта: Codable, Sendable {
    let схема: String
    let исходныйХэш: String
    let лексемы: [ПозицияПереводаСвифта]
    let конецПрофиля: Int
}

enum ПереводСвифта {
    static func хэш(_ байты: Data) -> String {
        SHA256.hash(data: байты).map { String(format: "%02x", $0) }.joined()
    }

    static func план(_ карта: Data, исходники: [String: Data]) throws -> ПланПереводаСвифта {
        let вход = try разобрать(карта)
        guard Set(вход.файлы.map(\.путь)) == Set(исходники.keys) else { throw ОтказПереводаСвифта.путь }
        var привязки: [String: (старое: String, новое: String, объявлений: Int)] = [:]
        for файл in вход.файлы {
            var локальные: Set<String> = []
            for привязка in файл.привязки {
                guard !привязка.идентификатор.isEmpty,
                      локальные.insert(привязка.идентификатор).inserted,
                      привязка.объявление != nil || !привязка.употребления.isEmpty else {
                    throw ОтказПереводаСвифта.объявление
                }
                let прежняя = привязки[привязка.идентификатор]
                guard прежняя == nil || (прежняя?.старое.utf8.elementsEqual(привязка.староеИмя.utf8) == true
                    && прежняя?.новое.utf8.elementsEqual(привязка.новоеИмя.utf8) == true) else {
                    throw ОтказПереводаСвифта.объявление
                }
                привязки[привязка.идентификатор] = (привязка.староеИмя, привязка.новоеИмя,
                    (прежняя?.объявлений ?? 0) + (привязка.объявление == nil ? 0 : 1))
            }
        }
        guard привязки.values.allSatisfy({ $0.объявлений == 1 }) else { throw ОтказПереводаСвифта.объявление }
        var результаты: [ПланФайлаСвифта] = []
        for файл in вход.файлы {
            guard let байты = исходники[файл.путь], байты.count <= 4_194_304,
                  хэш(байты) == файл.исходныйХэш else { throw ОтказПереводаСвифта.хэш }
            guard let текст = String(data: байты, encoding: .utf8), Data(текст.utf8) == байты,
                  !байты.contains(0) else { throw ОтказПереводаСвифта.вход }
            let проверяемыйТекст = try префикс(байты, конец: файл.конецПрофиля)
            var лексер = ЛексерЯзыковогоДопуска(проверяемыйТекст, профильПеревода: true)
            let лексемы = try лексер.прочитать()
            let позиции = try позицииЛексем(лексемы, текст: проверяемыйТекст)
            var полныйЛексер = ЛексерЯзыковогоДопуска(текст)
            let полныйИнвентарь = файл.конецПрофиля == nil ? лексемы : try полныйЛексер.прочитать()
            let ролиОбъявлений = try роли(полныйИнвентарь)
            // Полный инвентарь служит только консервативной проверке коллизий; перевод ограничен профилем.
            let имена = Set(полныйИнвентарь.filter(\.имя).map { $0.текст.precomposedStringWithCanonicalMapping })
            var новыеИмена: Set<String> = []
            var выбранные: Set<Int> = []
            var замены: [ЗаменаПереводаСвифта] = []
            for привязка in файл.привязки {
                guard привязка.староеИмя != "_", допустимоеИмя(привязка.новоеИмя),
                      !имена.contains(привязка.новоеИмя), новыеИмена.insert(привязка.новоеИмя).inserted
                else { throw ОтказПереводаСвифта.коллизия }
                for начало in [привязка.объявление].compactMap({ $0 }) + привязка.употребления {
                    guard начало >= 0, выбранные.insert(начало).inserted,
                          let номер = позиции[начало], лексемы[номер].имя,
                          лексемы[номер].текст.utf8.elementsEqual(привязка.староеИмя.utf8),
                          начало <= байты.count - привязка.староеИмя.utf8.count else {
                        throw ОтказПереводаСвифта.позиция
                    }
                    let конец = начало + привязка.староеИмя.utf8.count
                    guard байты[начало..<конец].elementsEqual(привязка.староеИмя.utf8) else {
                        throw ОтказПереводаСвифта.позиция
                    }
                    if начало == привязка.объявление {
                        guard ролиОбъявлений.contains(ключПозиции(лексемы[номер])) else {
                            throw ОтказПереводаСвифта.объявление
                        }
                    } else if ролиОбъявлений.contains(ключПозиции(лексемы[номер])) {
                        throw ОтказПереводаСвифта.объявление
                    }
                    замены.append(.init(привязка: привязка.идентификатор,
                        объявление: начало == привязка.объявление, начало: начало, конец: конец,
                        староеИмя: привязка.староеИмя, новоеИмя: привязка.новоеИмя))
                }
            }
            замены.sort { $0.начало < $1.начало }
            var конецПредыдущей = 0
            var будущие = Data()
            var промежутки = Data()
            for замена in замены {
                guard замена.начало >= конецПредыдущей else { throw ОтказПереводаСвифта.позиция }
                let промежуток = байты[конецПредыдущей..<замена.начало]
                будущие.append(промежуток)
                промежутки.append(contentsOf: "\(промежуток.count):".utf8)
                промежутки.append(промежуток)
                будущие.append(contentsOf: замена.новоеИмя.utf8)
                конецПредыдущей = замена.конец
            }
            let хвост = байты[конецПредыдущей...]
            будущие.append(хвост)
            промежутки.append(contentsOf: "\(хвост.count):".utf8)
            промежутки.append(хвост)
            результаты.append(.init(путь: файл.путь, исходныйХэш: хэш(байты), будущийХэш: хэш(будущие),
                хэшНеизменныхПромежутков: хэш(промежутки), будущиеБайты: будущие, замены: замены,
                конецПрофиля: файл.конецПрофиля))
        }
        return .init(схема: "fum.план-позиций-свифт.1", хэшКарты: хэш(карта), файлы: результаты)
    }

    static func лексемы(_ байты: Data, конец: Int? = nil) throws -> ЛексемыПереводаСвифта {
        guard байты.count <= 4_194_304, let текст = String(data: байты, encoding: .utf8),
              Data(текст.utf8) == байты, !байты.contains(0) else { throw ОтказПереводаСвифта.вход }
        let проверяемыйТекст = try префикс(байты, конец: конец)
        var лексер = ЛексерЯзыковогоДопуска(проверяемыйТекст, профильПеревода: true)
        let лексемы = try лексер.прочитать()
        let позиции = try позицииЛексем(лексемы, текст: проверяемыйТекст)
        var полныйЛексер = ЛексерЯзыковогоДопуска(текст)
        let ролиОбъявлений = try роли(конец == nil ? лексемы : полныйЛексер.прочитать())
        let результат = позиции.sorted { $0.key < $1.key }.map { начало, номер in
            let лексема = лексемы[номер]
            return ПозицияПереводаСвифта(текст: лексема.текст, начало: начало,
                конец: начало + лексема.текст.utf8.count, строка: лексема.строка, столбец: лексема.столбец,
                экранирована: лексема.экранирована, объявление: ролиОбъявлений.contains(ключПозиции(лексема)))
        }
        return .init(схема: "fum.лексемы-позиций-свифт.1", исходныйХэш: хэш(байты), лексемы: результат,
            конецПрофиля: конец ?? байты.count)
    }

    private static func префикс(_ байты: Data, конец: Int?) throws -> String {
        let предел = конец ?? байты.count
        guard предел > 0, предел <= байты.count,
              предел == байты.count || байты[предел - 1] == 10 || байты[предел - 1] == 13,
              !(предел < байты.count && байты[предел - 1] == 13 && байты[предел] == 10),
              let текст = String(data: байты.prefix(предел), encoding: .utf8) else { throw ОтказПереводаСвифта.профиль }
        return текст
    }

    static func разобрать(_ байты: Data) throws -> КартаПереводаСвифта {
        guard байты.count <= 1_048_576, let текст = String(data: байты, encoding: .utf8) else {
            throw ОтказПереводаСвифта.вход
        }
        // Прежний FUMA engine проверяет raw JSON, включая повторные ключи и целые числа.
        let оператор = try ОпределениеОператора.разобрать(Data("""
        {"схема":"fum.определение-оператора.1","идентификатор":"fum.прочитать-карту-позиций-свифт","версия":1,"правила":[],"шаги":[{"идентификатор":"прочитать","оператор":"вычислить-JSON","аргументы":{"граф":{"схема":"fuma.граф-JSON.1","числа":"целые64-без-дробей","переменные":[],"результат":["переменная","вход"]}}}]}
        """.utf8))
        let исполнение = try AutomationExecutor.выполнить(оператор, вход: .текст(текст))
        guard case .текст(let результат) = исполнение.результат else { throw ОтказПереводаСвифта.вход }
        let карта = try JSONDecoder().decode(КартаПереводаСвифта.self, from: Data(результат.utf8))
        let формат: JSONSerialization.WritingOptions = [.sortedKeys, .withoutEscapingSlashes]
        guard try JSONSerialization.data(withJSONObject: JSONSerialization.jsonObject(with: байты), options: формат)
                == JSONSerialization.data(withJSONObject: JSONSerialization.jsonObject(with: JSONEncoder().encode(карта)), options: формат),
              карта.схема == "fum.карта-позиций-свифт.1", !карта.файлы.isEmpty,
              карта.файлы.count <= 64 else { throw ОтказПереводаСвифта.вход }
        var пути: Set<String> = []
        for файл in карта.файлы {
            guard допустимыйПуть(файл.путь), пути.insert(файл.путь.lowercased()).inserted,
                  !файл.привязки.isEmpty, файл.привязки.count <= 4096,
                  файл.привязки.allSatisfy({ $0.употребления.count <= 16384 }) else {
                throw ОтказПереводаСвифта.путь
            }
        }
        return карта
    }

    static func допустимыйПуть(_ путь: String) -> Bool {
        путь.hasSuffix(".swift") && !путь.hasPrefix("/") && !путь.hasPrefix("Proyekcii/")
            && !путь.utf8.contains(0) && путь.utf8.elementsEqual(путь.precomposedStringWithCanonicalMapping.utf8)
            && путь.split(separator: "/", omittingEmptySubsequences: false).allSatisfy {
                !$0.isEmpty && $0 != "." && $0 != ".." && $0 != ".git"
            }
    }

    private static func допустимоеИмя(_ имя: String) -> Bool {
        let символы = Array(имя.unicodeScalars)
        guard let первый = символы.first,
              имя.utf8.elementsEqual(имя.precomposedStringWithCanonicalMapping.utf8),
              ОрфографияОбъявлений.причина(имя) == nil else { return false }
        let буква: (Unicode.Scalar) -> Bool = { (0x0410...0x044f).contains($0.value) || $0 == "ё" || $0 == "Ё" }
        return (первый == "_" || буква(первый)) && символы.contains(where: буква)
    }

    private static func роли(_ лексемы: [ЛексемаЯзыковогоДопуска]) throws -> Set<String> {
        Set(try СканерОбъявлений.прочитать(лексемы, профильРолей: true).map { ключПозиции($0.имя) })
    }

    private static func ключПозиции(_ лексема: ЛексемаЯзыковогоДопуска) -> String {
        "\(лексема.строка):\(лексема.столбец)"
    }

    private static func позицииЛексем(_ лексемы: [ЛексемаЯзыковогоДопуска], текст: String) throws -> [Int: Int] {
        let символы = Array(текст.unicodeScalars)
        var началаСтрок = [0]
        var байтовыеПозиции = [0]
        for номер in символы.indices {
            let символ = символы[номер]
            байтовыеПозиции.append(байтовыеПозиции.last! + символ.utf8.count)
            if символ == "\r" || (символ == "\n" && (номер == 0 || символы[номер - 1] != "\r")) {
                началаСтрок.append(номер + (символ == "\r" && номер + 1 < символы.count && символы[номер + 1] == "\n" ? 2 : 1))
            }
        }
        var результат: [Int: Int] = [:]
        for (номер, лексема) in лексемы.enumerated() where лексема.имя {
            let позиция = началаСтрок[лексема.строка - 1] + лексема.столбец - 1 + (лексема.экранирована ? 1 : 0)
            guard позиция >= 0, позиция < байтовыеПозиции.count else { throw ОтказПереводаСвифта.позиция }
            результат[байтовыеПозиции[позиция]] = номер
        }
        return результат
    }
}

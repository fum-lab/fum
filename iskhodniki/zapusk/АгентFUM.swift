            идентификатор: позиция.идентификаторАртефакта,
            поколение: позиция.поколение,
            как: НагрузкаВопросОтвета.self) else { return nil }
        let artifact = restored.артефакт
        guard restored.квитанция.описание.идентификатор == позиция.идентификаторЗаписи,
              restored.квитанция.хэш == позиция.sha256Записи,
              artifact.идентификатор == позиция.идентификаторАртефакта,
              artifact.поколение == позиция.поколение,
              artifact.назначениеПерехода == "fum.p5.agent-route/v2" else {
            throw ОшибкаАгентаFUM.квитанцияНеСовпадает
        }
        let eventBytes = Data(artifact.содержимое.вопрос.utf8)
        let payloadBytes = Data(artifact.содержимое.ответ.utf8)
        let event = try Self.разобрать(artifact.содержимое.вопрос,
                                       как: СобытиеМаршрутаАгентаFUM.self)
        let payload = try Self.разобрать(artifact.содержимое.ответ,
                                         как: СодержимоеПамятиАгентаFUM.self)
        let base = "agent://\(позиция.идентификаторАртефакта)/\(позиция.поколение)"
        guard payload.схема == "fum.агент-P5.память.2",
              payload.идентификаторХранилища == позиция.идентификаторХранилища,
              payload.идентификаторАгента == позиция.идентификаторАгента,
              payload.событие == event,
              payload.снимок.идентификаторАгента == агента.идентификатор,

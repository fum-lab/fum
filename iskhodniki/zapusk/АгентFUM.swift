            идентификаторХранилища: storeID, идентификаторАгента: agentID,
            идентификаторАртефакта: artifactID, поколение: snapshot.поколение,
            идентификаторЗаписи: recordID, sha256Записи: recordSHA,
            sha256Перехода: transitionSHA, предшественник: predecessor)
    }

    private static func состояниеПреемника(для снимок: СнимокАгентаFUM) -> СостояниеПреемника {
        switch снимок.состояние {
        case .неизвестныйИсход: return .неизвестно
        case .готоваКЗакрытию: return .ожидает
        case .удержана: return .неВыполнено
        case .безРаботы, .назначена, .выполняется, .ожидаетРешенияПотребителя:
            return .ожидает
        }
    }

    private static func идентификаторАртефакта(
        идентификаторХранилища: String, идентификаторАгента: String
    ) -> String {
        var bytes = Data("fum.p5.agent.namespace.v2\0".utf8)
        Self.добавитьДлину(идентификаторХранилища.utf8.count, в: &bytes)
        bytes.append(contentsOf: идентификаторХранилища.utf8)
        Self.добавитьДлину(идентификаторАгента.utf8.count, в: &bytes)
        bytes.append(contentsOf: идентификаторАгента.utf8)
        return "fum-p5-agent-" + Self.sha256(bytes)
    }

    private static func добавитьДлину(_ длина: Int, в bytes: inout Data) {
        let value = UInt64(длина)
        for shift in stride(from: 56, through: 0, by: -8) {
            bytes.append(UInt8((value >> shift) & 0xff))
        }
    }

    private static func допустимаяСсылка(_ ссылка: ЗакреплённаяСсылка) -> Bool {
        !ссылка.адрес.isEmpty && ссылка.адрес.utf8.count <= 512 &&
            !ссылка.версия.isEmpty && ссылка.версия.utf8.count <= 128 &&
            ИдентичностьАгентаFUM.верныйSHA256(ссылка.sha256)
    }

    private static func кодировать<T: Encodable>(_ значение: T) throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        do { return try encoder.encode(значение) }
        catch { throw ОшибкаАгентаFUM.кодирование }
    }

    private static func разобрать<T: Decodable>(_ строка: String, как тип: T.Type) throws -> T {
        do { return try JSONDecoder().decode(тип, from: Data(строка.utf8)) }
        catch { throw ОшибкаАгентаFUM.квитанцияНеСовпадает }
    }

    private static func sha256(_ данные: Data) -> String {
        SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
    }

    private static func sha256Перехода(_ событие: Data, _ снимок: Data) -> String {
        var bytes = событие
        bytes.append(0)
        bytes.append(снимок)
        return sha256(bytes)
    }

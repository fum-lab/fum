/// Записывает один путь через существующий A12 и адресно подтверждает каждого предшественника.
public actor ПамятьАгентаFUM {
    private let агент: ИдентичностьАгентаFUM
    private let записатьВA12: @Sendable (ВходВопросОтвета) throws -> ИсходПисателяАгентаFUM
    private let прочитатьA12: @Sendable (ПозицияПамятиАгентаFUM) throws
        -> ВосстановленнаяЗаписьАгентаFUM?
    private var продолжение: ПродолжениеПамятиАгентаFUM
    private var отсутствиеНеизвестнойЗаписиНаблюдено = false

    private init(агент: ИдентичностьАгентаFUM,
                 продолжение: ПродолжениеПамятиАгентаFUM,
                 отсутствиеНеизвестнойЗаписиНаблюдено: Bool = false,
                 записать: @escaping @Sendable (ВходВопросОтвета) throws
                    -> ИсходПисателяАгентаFUM,
                 прочитать: @escaping @Sendable (ПозицияПамятиАгентаFUM) throws
                    -> ВосстановленнаяЗаписьАгентаFUM?) {
        self.агент = агент
        self.продолжение = продолжение
        self.отсутствиеНеизвестнойЗаписиНаблюдено = отсутствиеНеизвестнойЗаписиНаблюдено
        записатьВA12 = записать
        прочитатьA12 = прочитать
    }

    /// Новое открытие разрешено после точной проверки слота генезиса только для чтения.
    public static func открытьНовое(для агента: ИдентичностьАгентаFUM) throws -> Self {
        try агента.проверить()
        let хранилище = ХранилищеАртефактов(
            кореньХранилища: агента.собственнаяПамять.кореньХранилища)
        let id = идентификаторАртефакта(
            идентификаторХранилища: агента.собственнаяПамять.идентификаторХранилища,
            идентификаторАгента: агента.идентификатор)
        guard try хранилище.восстановитьПреемника(
            идентификатор: id, поколение: 1, как: НагрузкаВопросОтвета.self) == nil else {
            throw ОшибкаАгентаFUM.неверноеПродолжение
        }
        let (писатель, читатель) = зависимости(агент: агента, хранилище: хранилище)
        let начальное = ПродолжениеПамятиАгентаFUM(
            идентификаторХранилища: агента.собственнаяПамять.идентификаторХранилища,
            идентификаторАгента: агента.идентификатор,
            снимок: .пустой(для: агента), позиция: nil,
            неизвестнаяЗапись: nil, решениеПоНеизвестнойЗаписи: nil)
        return Self(агент: агента, продолжение: начальное,
                    записать: писатель, прочитать: читатель)
    }

    /// Открытие продолжения восстанавливает точную позицию либо удерживает токен UNKNOWN.
    public static func открыть(для агента: ИдентичностьАгентаFUM,
                               продолжение: ПродолжениеПамятиАгентаFUM) throws -> Self {
        try агента.проверить()
        try проверить(продолжение, для: агента)
        let хранилище = ХранилищеАртефактов(
            кореньХранилища: агента.собственнаяПамять.кореньХранилища)
        let (писатель, читатель) = зависимости(агент: агента, хранилище: хранилище)

        if let token = продолжение.неизвестнаяЗапись {
            guard token.предыдущийСнимок == продолжение.снимок,
                  token.позицияПопытки.предшественник == продолжение.позиция?.ссылка else {
                throw ОшибкаАгентаFUM.неверноеПродолжение
            }
            if let предыдущаяПозиция = продолжение.позиция {
                guard let восстановленныйПредок = try читатель(предыдущаяПозиция),
                      восстановленныйПредок.снимок == продолжение.снимок else {
                    throw ОшибкаАгентаFUM.предшественникНеПодтверждён
                }
            } else if продолжение.снимок.поколение != 0 {
                throw ОшибкаАгентаFUM.предшественникНеПодтверждён
            }

            if let найденный = try читатель(token.позицияПопытки) {
                try проверить(найденный, соответствует: token, агент: агента)
                let подтверждённоеПродолжение = ПродолжениеПамятиАгентаFUM(
                    идентификаторХранилища: token.позицияПопытки.идентификаторХранилища,
                    идентификаторАгента: агента.идентификатор,
                    снимок: найденный.снимок, позиция: найденный.позиция,
                    неизвестнаяЗапись: nil, решениеПоНеизвестнойЗаписи: nil)
                return Self(агент: агента, продолжение: подтверждённоеПродолжение,
                            записать: писатель, прочитать: читатель)
            }
            return Self(агент: агента, продолжение: продолжение,
                              отсутствиеНеизвестнойЗаписиНаблюдено: true,
                              записать: писатель, прочитать: читатель)
        }

        if let позиция = продолжение.позиция {
            guard let восстановленный = try читатель(позиция),
                  восстановленный.снимок == продолжение.снимок else {
                throw ОшибкаАгентаFUM.предшественникНеПодтверждён
            }
        } else {
            guard продолжение.снимок.поколение == 0,
                  try хранилище.восстановитьПреемника(
                    идентификатор: идентификаторАртефакта(
                        идентификаторХранилища: продолжение.идентификаторХранилища,
                        идентификаторАгента: агента.идентификатор),
                    поколение: 1, как: НагрузкаВопросОтвета.self) == nil else {
                throw ОшибкаАгентаFUM.неверноеПродолжение
            }
        }
        return Self(агент: агента, продолжение: продолжение,
                    записать: писатель, прочитать: читатель)
    }


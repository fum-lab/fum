/// Минимальная идентичность узла с точной ссылкой на ожидаемого потребителя.
public struct ИдентичностьАгентаFUM: Codable, Equatable, Sendable {
    public let идентификатор: String
    public let цель: String
    public let родитель: СсылкаАгентаFUM?
    public let ожидаемыйПотребитель: СсылкаАгентаFUM
    public let собственнаяЗапись: ОбластьЗаписиАгентаFUM
    public let собственнаяПамять: СобственнаяПамятьАгентаFUM
    public let локальныеПравила: ЗакреплённаяСсылка
    public let собственныйПлан: ЗакреплённаяСсылка
    public let возможностиМодели: ВозможностиМоделиАгентаFUM
    public let пределыРесурсов: ПределыРесурсовАгентаFUM

    public init(идентификатор: String, цель: String, родитель: СсылкаАгентаFUM?,
                ожидаемыйПотребитель: СсылкаАгентаFUM,
                собственнаяЗапись: ОбластьЗаписиАгентаFUM,
                собственнаяПамять: СобственнаяПамятьАгентаFUM,
                локальныеПравила: ЗакреплённаяСсылка,
                собственныйПлан: ЗакреплённаяСсылка,
                возможностиМодели: ВозможностиМоделиАгентаFUM,
                пределыРесурсов: ПределыРесурсовАгентаFUM) {
        self.идентификатор = идентификатор
        self.цель = цель
        self.родитель = родитель
        self.ожидаемыйПотребитель = ожидаемыйПотребитель
        self.собственнаяЗапись = собственнаяЗапись
        self.собственнаяПамять = собственнаяПамять
        self.локальныеПравила = локальныеПравила
        self.собственныйПлан = собственныйПлан
        self.возможностиМодели = возможностиМодели
        self.пределыРесурсов = пределыРесурсов
    }

    public func проверить() throws {
        guard Self.допустимыйИдентификатор(идентификатор),
              !цель.isEmpty, цель.utf8.count <= 2048,
              Self.допустимаяСсылкаАгента(ожидаемыйПотребитель),
              ожидаемыйПотребитель.идентификатор != идентификатор,
              родитель.map({
                  Self.допустимаяСсылкаАгента($0) &&
                      $0.идентификатор != идентификатор &&
                      $0 == ожидаемыйПотребитель
              }) ?? true,
              !собственнаяЗапись.рабочееДерево.isEmpty,
              собственнаяЗапись.рабочееДерево.utf8.count <= 1024,
              собственнаяЗапись.полныйRef.hasPrefix("refs/heads/"),
              собственнаяЗапись.полныйRef.utf8.count <= 512,
              !собственнаяЗапись.разрешённыеПути.isEmpty,
              собственнаяЗапись.разрешённыеПути.count <= 128,
              Set(собственнаяЗапись.разрешённыеПути).count ==
                  собственнаяЗапись.разрешённыеПути.count,
              собственнаяЗапись.разрешённыеПути.allSatisfy(Self.допустимыйОтносительныйПуть),
              !собственнаяПамять.идентификаторХранилища.isEmpty,
              собственнаяПамять.идентификаторХранилища.utf8.count <= 128,
              собственнаяПамять.кореньХранилища.hasPrefix("/"),
              собственнаяПамять.кореньХранилища.utf8.count <= 4096,
              Self.допустимаяСсылка(локальныеПравила),
              Self.допустимаяСсылка(собственныйПлан),
              !возможностиМодели.метки.isEmpty,
              возможностиМодели.метки.count <= 32,
              возможностиМодели.метки.allSatisfy({
                  !$0.isEmpty && $0.utf8.count <= 128
              }),
              пределыРесурсов.максимумБайтовЗаписи >= 1024,
              пределыРесурсов.максимумБайтовЗаписи <= 262_144 else {
            throw ОшибкаАгентаFUM.некорректнаяИдентичность
        }
    }

    fileprivate static func допустимыйИдентификатор(_ значение: String) -> Bool {
        let байты = Array(значение.utf8)
        return !байты.isEmpty && байты.count <= 128 && байты.allSatisfy {
            (0x30...0x39).contains($0) || (0x41...0x5a).contains($0) ||
                (0x61...0x7a).contains($0) || $0 == 0x2d || $0 == 0x2e || $0 == 0x5f
        }
    }

    fileprivate static func верныйSHA256(_ значение: String) -> Bool {
        let байты = Array(значение.utf8)
        return байты.count == 64 && байты.allSatisfy {
            (0x30...0x39).contains($0) || (0x61...0x66).contains($0)
        }
    }

    fileprivate static func допустимаяСсылкаАгента(_ ссылка: СсылкаАгентаFUM) -> Bool {
        допустимыйИдентификатор(ссылка.идентификатор) &&
            !ссылка.цель.isEmpty && ссылка.цель.utf8.count <= 2048
    }

    private static func допустимаяСсылка(_ ссылка: ЗакреплённаяСсылка) -> Bool {
        !ссылка.адрес.isEmpty && ссылка.адрес.utf8.count <= 512 &&
            !ссылка.версия.isEmpty && ссылка.версия.utf8.count <= 128 &&
            верныйSHA256(ссылка.sha256)
    }

    private static func допустимыйОтносительныйПуть(_ путь: String) -> Bool {
        guard !путь.isEmpty, !путь.hasPrefix("/"), !путь.contains("\\") else { return false }
        return путь.split(separator: "/", omittingEmptySubsequences: false).allSatisfy {
            !$0.isEmpty && $0 != "." && $0 != ".."
        }
    }
}


public enum МаршрутАгентаFUM {
    /// Чисто готовит переход. Даже принятие результата здесь не закрывает назначение.
    public static func подготовить(_ событие: СобытиеМаршрутаАгентаFUM,
                                   после снимок: СнимокАгентаFUM,
                                   для агента: ИдентичностьАгентаFUM) throws -> СнимокАгентаFUM {
        try агента.проверить()
        try снимок.проверить(для: агента)
        guard снимок.поколение < UInt64.max else {
            throw ОшибкаАгентаFUM.поколениеПереполнено
        }

        var состояние = снимок.состояние
        var работа = снимок.работа
        var результат = снимок.результат
        var обратнаяСвязь = снимок.обратнаяСвязь
        var остаток = снимок.остаток

        switch событие {
        case .генезис:
            guard снимок.поколение == 0, снимок.состояние == .безРаботы else {
                throw ОшибкаАгентаFUM.недопустимыйПереход
            }
        case .назначена(let новаяРабота):
            try новаяРабота.проверить(для: агента)
            if состояние == .назначена, работа == новаяРабота { return снимок }
            guard состояние == .безРаботы, снимок.поколение == 1 else {
                throw ОшибкаАгентаFUM.недопустимыйПереход
            }
            работа = новаяРабота
            состояние = .назначена
        case .началась(let идентификаторРаботы):
            guard let работа, работа.идентификатор == идентификаторРаботы else {
                throw ОшибкаАгентаFUM.работаНеНайдена
            }
            if состояние == .выполняется { return снимок }
            guard состояние == .назначена else { throw ОшибкаАгентаFUM.недопустимыйПереход }
            состояние = .выполняется
        case .поступилРезультат(let новыйРезультат):
            try новыйРезультат.проверить()
            guard let работа, работа.идентификатор == новыйРезультат.идентификаторРаботы else {
                throw ОшибкаАгентаFUM.работаНеНайдена
            }
            if результат == новыйРезультат { return снимок }
            guard состояние == .выполняется else { throw ОшибкаАгентаFUM.недопустимыйПереход }
            результат = новыйРезультат
            let совпадает = новыйРезультат.версияНазначения == работа.версияНазначения &&
                новыйРезультат.цель == работа.цель &&
                новыйРезультат.ссылкаНазначения == работа.ссылкаНазначения
            if !совпадает {
                состояние = .удержана
                остаток.append("Результат удержан: назначение, версия или цель не совпали.")
            } else {
                switch новыйРезультат.исход {
                case .выполнен:
                    состояние = .ожидаетРешенияПотребителя
                case .неВыполнен:
                    состояние = .удержана
                    остаток.append("Работа не выполнена; требуется явное решение потребителя.")
                case .неизвестен:
                    состояние = .неизвестныйИсход
                    остаток.append("UNKNOWN: повтор запрещён до адресной сверки и решения.")
                }
            }
        case .решениеПотребителя(let новоеРешение):
            try новоеРешение.проверить()
            guard let работа, работа.идентификатор == новоеРешение.идентификаторРаботы else {
                throw ОшибкаАгентаFUM.работаНеНайдена
            }
            if обратнаяСвязь == новоеРешение { return снимок }
            guard let результат else { throw ОшибкаАгентаFUM.недопустимыйПереход }
            guard состояние != .неизвестныйИсход, результат.исход != .неизвестен else {
                throw ОшибкаАгентаFUM.неизвестныйИсход
            }
            обратнаяСвязь = новоеРешение
            let точноСовпадает = состояние == .ожидаетРешенияПотребителя &&
                новоеРешение.потребитель == работа.ожидаемыйПотребитель &&
                новоеРешение.версияНазначения == работа.версияНазначения &&
                новоеРешение.цель == работа.цель &&
                новоеРешение.номерРезультата == результат.номерРезультата &&
                новоеРешение.ссылкаНазначения == работа.ссылкаНазначения &&
                новоеРешение.идентификаторРаботы == результат.идентификаторРаботы &&
                новоеРешение.версияНазначения == результат.версияНазначения &&
                новоеРешение.цель == результат.цель &&
                новоеРешение.ссылкаНазначения == результат.ссылкаНазначения
            guard точноСовпадает else {
                состояние = .удержана
                остаток += новоеРешение.остаток
                остаток.append("Обратная связь удержана: потребитель или binding не совпал.")
                break
            }
            остаток += новоеРешение.остаток
            switch новоеРешение.решение {
            case .принять:
                состояние = .готоваКЗакрытию
            case .отклонить, .удержать:
                состояние = .удержана
                остаток.append(новоеРешение.основание)
            }
        }

        guard остаток.count <= 32 else { throw ОшибкаАгентаFUM.некорректныйСнимок }
        let следующий = СнимокАгентаFUM(
            идентификаторАгента: агента.идентификатор,
            поколение: снимок.поколение + 1, состояние: состояние,
            работа: работа, результат: результат,
            обратнаяСвязь: обратнаяСвязь, остаток: остаток)
        try следующий.проверить(для: агента)
        return следующий
    }
}


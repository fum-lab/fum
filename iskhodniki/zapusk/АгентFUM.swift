/// Подготовленный снимок одного назначения. Терминальное закрытие выдаёт только A12 receipt.
public struct СнимокАгентаFUM: Codable, Equatable, Sendable {
    public let идентификаторАгента: String
    public let поколение: UInt64
    public let состояние: СостояниеАгентаFUM
    public let работа: РаботаАгентаFUM?
    public let результат: РезультатРаботыАгентаFUM?
    public let обратнаяСвязь: ОбратнаяСвязьПотребителяFUM?
    public let остаток: [String]

    init(идентификаторАгента: String, поколение: UInt64,
         состояние: СостояниеАгентаFUM, работа: РаботаАгентаFUM?,
         результат: РезультатРаботыАгентаFUM?,
         обратнаяСвязь: ОбратнаяСвязьПотребителяFUM?, остаток: [String]) {
        self.идентификаторАгента = идентификаторАгента
        self.поколение = поколение
        self.состояние = состояние
        self.работа = работа
        self.результат = результат
        self.обратнаяСвязь = обратнаяСвязь
        self.остаток = остаток
    }

    public static func пустой(для агента: ИдентичностьАгентаFUM) -> Self {
        Self(идентификаторАгента: агента.идентификатор, поколение: 0,
             состояние: .безРаботы, работа: nil, результат: nil,
             обратнаяСвязь: nil, остаток: [])
    }

    fileprivate func проверить(для агента: ИдентичностьАгентаFUM) throws {
        guard идентификаторАгента == агента.идентификатор,
              остаток.count <= 32,
              остаток.allSatisfy({ !$0.isEmpty && $0.utf8.count <= 1024 }) else {
            throw ОшибкаАгентаFUM.некорректныйСнимок
        }
        try работа?.проверить(для: агента)
        try результат?.проверить()
        try обратнаяСвязь?.проверить()
        if let работа, let результат,
           результат.идентификаторРаботы != работа.идентификатор {
            throw ОшибкаАгентаFUM.некорректныйСнимок
        }
        if let работа, let обратнаяСвязь,
           обратнаяСвязь.идентификаторРаботы != работа.идентификатор {
            throw ОшибкаАгентаFUM.некорректныйСнимок
        }

        switch состояние {
        case .безРаботы:
            guard (поколение == 0 || поколение == 1),
                  работа == nil, результат == nil, обратнаяСвязь == nil else {
                throw ОшибкаАгентаFUM.некорректныйСнимок
            }
        case .назначена, .выполняется:
            guard поколение > 1, работа != nil, результат == nil,
                  обратнаяСвязь == nil else {
                throw ОшибкаАгентаFUM.некорректныйСнимок
            }
        case .ожидаетРешенияПотребителя:
            guard let работа, let результат, поколение > 1,
                  результат.исход == .выполнен,
                  результат.версияНазначения == работа.версияНазначения,
                  результат.цель == работа.цель,
                  результат.ссылкаНазначения == работа.ссылкаНазначения,
                  обратнаяСвязь == nil else {
                throw ОшибкаАгентаFUM.некорректныйСнимок
            }
        case .неизвестныйИсход:
            guard let работа, let результат, поколение > 1,
                  результат.исход == .неизвестен,
                  результат.версияНазначения == работа.версияНазначения,
                  результат.цель == работа.цель,
                  результат.ссылкаНазначения == работа.ссылкаНазначения,
                  обратнаяСвязь == nil else {
                throw ОшибкаАгентаFUM.некорректныйСнимок
            }
        case .готоваКЗакрытию:
            guard let работа, let результат, let обратнаяСвязь, поколение > 1,
                  результат.исход == .выполнен,
                  результат.идентификаторРаботы == работа.идентификатор,
                  результат.версияНазначения == работа.версияНазначения,
                  результат.цель == работа.цель,
                  результат.ссылкаНазначения == работа.ссылкаНазначения,
                  обратнаяСвязь.решение == .принять,
                  обратнаяСвязь.идентификаторРаботы == результат.идентификаторРаботы,
                  обратнаяСвязь.версияНазначения == результат.версияНазначения,
                  обратнаяСвязь.цель == результат.цель,
                  обратнаяСвязь.номерРезультата == результат.номерРезультата,

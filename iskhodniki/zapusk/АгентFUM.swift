    public func сохранить(_ событие: СобытиеМаршрутаАгентаFUM,
                          время: String) throws -> ИсходСохраненияАгентаFUM {
        if продолжение.неизвестнаяЗапись != nil {
            return .удержан(
                продолжение: продолжение,
                причина: "UNKNOWN удерживается до точной сверки и типизированного решения.")
        }
        if продолжение.решениеПоНеизвестнойЗаписи != nil {
            return .удержан(
                продолжение: продолжение,
                причина: "Решение остановило неизвестную попытку; новый запуск вне этого среза.")
        }
        let следующий = try МаршрутАгентаFUM.подготовить(
            событие, после: продолжение.снимок, для: агент)
        guard следующий != продолжение.снимок else {
            return .точныйПовтор(продолжение: продолжение)
        }

        let предшественник = продолжение.позиция
        if событие == .генезис {
            guard предшественник == nil, продолжение.снимок.поколение == 0 else {
                throw ОшибкаАгентаFUM.предшественникНеПодтверждён
            }
        } else {
            guard let предшественник,
                  let восстановленный = try прочитатьA12(предшественник),
                  восстановленный.позиция == предшественник,
                  восстановленный.снимок == продолжение.снимок else {
                throw ОшибкаАгентаFUM.предшественникНеПодтверждён
            }
        }

        let artifactID = Self.идентификаторАртефакта(
            идентификаторХранилища: агент.собственнаяПамять.идентификаторХранилища,
            идентификаторАгента: агент.идентификатор)
        let bytesEvent = try Self.кодировать(событие)
        let payload = СодержимоеПамятиАгентаFUM(
            схема: "fum.агент-P5.память.2",
            идентификаторХранилища: агент.собственнаяПамять.идентификаторХранилища,
            идентификаторАгента: агент.идентификатор,
            событие: событие, снимок: следующий,
            предшественник: предшественник?.ссылка)
        let bytesPayload = try Self.кодировать(payload)
        guard bytesEvent.count <= агент.пределыРесурсов.максимумБайтовЗаписи,
              bytesPayload.count <= агент.пределыРесурсов.максимумБайтовЗаписи,
              let eventText = String(data: bytesEvent, encoding: .utf8),
              let payloadText = String(data: bytesPayload, encoding: .utf8) else {
            throw ОшибкаАгентаFUM.пределПамяти
        }
        let shaTransition = Self.sha256Перехода(bytesEvent, bytesPayload)
        let base = "agent://\(artifactID)/\(следующий.поколение)"
        let version = "fum.агент-P5/2"
        let input = ВходВопросОтвета(
            идентификатор: artifactID, поколение: следующий.поколение,
            время: время, назначениеПерехода: "fum.p5.agent-route/v2",
            вопрос: eventText, ответ: payloadText,
            ссылкаВопроса: ЗакреплённаяСсылка(
                адрес: base + "/event", версия: version, sha256: Self.sha256(bytesEvent)),
            ссылкаОтвета: ЗакреплённаяСсылка(
                адрес: base + "/payload", версия: version, sha256: Self.sha256(bytesPayload)),
            состояние: Self.состояниеПреемника(для: следующий))

        switch try записатьВA12(input) {
        case .подтверждён(let recordID, let recordSHA):
            let position = Self.позиция(
                storeID: агент.собственнаяПамять.идентификаторХранилища,
                agentID: агент.идентификатор, artifactID: artifactID,
                snapshot: следующий, recordID: recordID, recordSHA: recordSHA,
                transitionSHA: shaTransition, predecessor: предшественник?.ссылка)
            let newContinuation = ПродолжениеПамятиАгентаFUM(
                идентификаторХранилища: агент.собственнаяПамять.идентификаторХранилища,
                идентификаторАгента: агент.идентификатор,
                снимок: следующий, позиция: position,
                неизвестнаяЗапись: nil, решениеПоНеизвестнойЗаписи: nil)
            продолжение = newContinuation
            if следующий.состояние == .готоваКЗакрытию {
                let closure = ПодтверждённоеЗакрытиеАгентаFUM(
                    снимок: следующий, квитанция: position)
                return .закрытиеПодтверждено(closure, продолжение: newContinuation)
            }
            return .подтверждён(продолжение: newContinuation)

        case .неизвестен(let recordID, let recordSHA):
            let position = Self.позиция(
                storeID: агент.собственнаяПамять.идентификаторХранилища,
                agentID: агент.идентификатор, artifactID: artifactID,
                snapshot: следующий, recordID: recordID, recordSHA: recordSHA,
                transitionSHA: shaTransition, predecessor: предшественник?.ссылка)
            let token = НеизвестнаяЗаписьАгентаFUM(
                позицияПопытки: position, предыдущийСнимок: продолжение.снимок,
                событие: событие, предложенныйСнимок: следующий, время: время)
            let unresolved = ПродолжениеПамятиАгентаFUM(
                идентификаторХранилища: агент.собственнаяПамять.идентификаторХранилища,
                идентификаторАгента: агент.идентификатор,
                снимок: продолжение.снимок, позиция: предшественник,
                неизвестнаяЗапись: token, решениеПоНеизвестнойЗаписи: nil)
            продолжение = unresolved
            return .неизвестен(предыдущийСнимок: unresolved.снимок,
                               продолжение: unresolved)
        }
    }


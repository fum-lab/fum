              artifact.содержимое.ссылкаОтвета.sha256 == Self.sha256(payloadBytes),
              Self.sha256Перехода(eventBytes, payloadBytes) == позиция.sha256Перехода else {
            throw ОшибкаАгентаFUM.квитанцияНеСовпадает
        }
        try payload.снимок.проверить(для: агента)
        let computed = Self.позиция(
            storeID: позиция.идентификаторХранилища, agentID: агента.идентификатор,
            artifactID: позиция.идентификаторАртефакта, snapshot: payload.снимок,

              Self.допустимаяСсылка(решение.наблюдение),
              решение.версияНаблюдаемогоСостояния > 0,
              !решение.основание.isEmpty, решение.основание.utf8.count <= 2048 else {
            throw ОшибкаАгентаFUM.неверноеРешениеНеизвестнойЗаписи
        }
        if let работа = token.предложенныйСнимок.работа {
            guard решение.назначение == работа.ссылкаНазначения else {
                throw ОшибкаАгентаFUM.неверноеРешениеНеизвестнойЗаписи
            }
        } else {
            guard решение.назначение == агент.собственныйПлан else {
                throw ОшибкаАгентаFUM.неверноеРешениеНеизвестнойЗаписи
            }
        }
        let завершение = ПродолжениеПамятиАгентаFUM(
            идентификаторХранилища: продолжение.идентификаторХранилища,
            идентификаторАгента: продолжение.идентификаторАгента,
            снимок: продолжение.снимок, позиция: продолжение.позиция,
            неизвестнаяЗапись: token, решениеПоНеизвестнойЗаписи: решение)
        продолжение = завершение
        return завершение
    }


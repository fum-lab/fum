                  обратнаяСвязь.потребитель == работа.ожидаемыйПотребитель else {
                throw ОшибкаАгентаFUM.некорректныйСнимок
            }
        case .удержана:
            guard поколение > 1, работа != nil,
                  результат != nil || обратнаяСвязь != nil else {
                throw ОшибкаАгентаFUM.некорректныйСнимок
            }
        }
    }

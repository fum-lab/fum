            время: artifact.время)
    }

    fileprivate static func проверить(_ запись: ВосстановленнаяЗаписьАгентаFUM,
                                      соответствует token: НеизвестнаяЗаписьАгентаFUM,
                                      агент: ИдентичностьАгентаFUM) throws {
        try проверить(запись.позиция, для: агент)
        guard запись.позиция == token.позицияПопытки,
              запись.предшественник == token.позицияПопытки.предшественник,
              запись.событие == token.событие,
              запись.снимок == token.предложенныйСнимок,
              запись.время == token.время else {
            throw ОшибкаАгентаFUM.квитанцияНеСовпадает
        }
    }

    private static func проверить(_ позиция: ПозицияПамятиАгентаFUM,
                                  для агента: ИдентичностьАгентаFUM) throws {
        guard позиция.идентификаторХранилища ==
                агента.собственнаяПамять.идентификаторХранилища,
              позиция.идентификаторАгента == агента.идентификатор,
              позиция.идентификаторАртефакта == идентификаторАртефакта(
                идентификаторХранилища: позиция.идентификаторХранилища,
                идентификаторАгента: позиция.идентификаторАгента),
              позиция.поколение > 0,
              !позиция.идентификаторЗаписи.isEmpty,
              позиция.идентификаторЗаписи.utf8.count <= 256,
              !позиция.идентификаторЗаписи.utf8.contains(0),
              ИдентичностьАгентаFUM.верныйSHA256(позиция.sha256Записи),
              ИдентичностьАгентаFUM.верныйSHA256(позиция.sha256Перехода),
              позиция.предшественник.map({
                  $0.идентификаторХранилища == позиция.идентификаторХранилища &&
                      $0.идентификаторАгента == позиция.идентификаторАгента &&
                      $0.идентификаторАртефакта == позиция.идентификаторАртефакта &&
                      $0.поколение < позиция.поколение &&
                      $0.поколение + 1 == позиция.поколение
              }) ?? (позиция.поколение == 1) else {
            throw ОшибкаАгентаFUM.неверноеПродолжение
        }
    }

    private static func проверить(_ продолжение: ПродолжениеПамятиАгентаFUM,
                                  для агента: ИдентичностьАгентаFUM) throws {
        guard продолжение.идентификаторХранилища ==
                агента.собственнаяПамять.идентификаторХранилища,
              продолжение.идентификаторАгента == агента.идентификатор else {
            throw ОшибкаАгентаFUM.неверноеПродолжение
        }
        try продолжение.снимок.проверить(для: агента)
        if let позиция = продолжение.позиция {
            try проверить(позиция, для: агента)
            guard позиция.поколение == продолжение.снимок.поколение else {
                throw ОшибкаАгентаFUM.неверноеПродолжение
            }
        } else if продолжение.снимок.поколение != 0 {
            throw ОшибкаАгентаFUM.неверноеПродолжение
        }
        if let token = продолжение.неизвестнаяЗапись {
            try проверить(token.позицияПопытки, для: агента)
            let подготовленныйСнимок = try МаршрутАгентаFUM.подготовить(
                token.событие, после: token.предыдущийСнимок, для: агента)
            let bytesEvent = try Self.кодировать(token.событие)
            let payload = СодержимоеПамятиАгентаFUM(
                схема: "fum.агент-P5.память.2",
                идентификаторХранилища: продолжение.идентификаторХранилища,
                идентификаторАгента: агента.идентификатор,
                событие: token.событие, снимок: token.предложенныйСнимок,
                предшественник: продолжение.позиция?.ссылка)
            let bytesPayload = try Self.кодировать(payload)
            guard token.предыдущийСнимок == продолжение.снимок,
                  продолжение.снимок.поколение < UInt64.max,
                  token.позицияПопытки.поколение == продолжение.снимок.поколение + 1,
                  token.позицияПопытки.поколение == token.предложенныйСнимок.поколение,
                  token.позицияПопытки.предшественник == продолжение.позиция?.ссылка,
                  token.предложенныйСнимок == подготовленныйСнимок,
                  token.время.utf8.count > 0, token.время.utf8.count <= 512,
                  token.позицияПопытки.sha256Перехода ==
                    sha256Перехода(bytesEvent, bytesPayload) else {
                throw ОшибкаАгентаFUM.неверноеПродолжение
            }
        }
        if let decision = продолжение.решениеПоНеизвестнойЗаписи {
            guard let token = продолжение.неизвестнаяЗапись,
                  decision.позицияПопытки == token.позицияПопытки.ссылка,
                  decision.потребитель == агента.ожидаемыйПотребитель,
                  Self.допустимаяСсылка(decision.назначение),
                  Self.допустимаяСсылка(decision.наблюдение),
                  decision.версияНаблюдаемогоСостояния > 0,
                  !decision.основание.isEmpty,
                  decision.основание.utf8.count <= 2048 else {
                throw ОшибкаАгентаFUM.неверноеПродолжение
            }
            if let работа = token.предложенныйСнимок.работа {
                guard decision.назначение == работа.ссылкаНазначения else {
                    throw ОшибкаАгентаFUM.неверноеПродолжение
                }
            } else {
                guard decision.назначение == агента.собственныйПлан else {
                    throw ОшибкаАгентаFUM.неверноеПродолжение
                }
            }
        }
    }

    private static func позиция(

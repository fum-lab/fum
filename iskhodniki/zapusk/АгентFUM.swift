              payload.предшественник == позиция.предшественник,
              artifact.состояние == Self.состояниеПреемника(для: payload.снимок),
              try Self.кодировать(event) == eventBytes,
              try Self.кодировать(payload) == payloadBytes,
              artifact.содержимое.ссылкаВопроса.адрес == base + "/event",
              artifact.содержимое.ссылкаОтвета.адрес == base + "/payload",
              artifact.содержимое.ссылкаВопроса.версия == "fum.агент-P5/2",

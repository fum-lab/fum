    private static func восстановить(_ позиция: ПозицияПамятиАгентаFUM,
                                     для агента: ИдентичностьАгентаFUM,
                                     через хранилище: ХранилищеАртефактов) throws
        -> ВосстановленнаяЗаписьАгентаFUM? {
        try проверить(позиция, для: агента)

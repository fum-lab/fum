/// Одно адресное назначение; очереди и выбор следующей работы отсутствуют.
public struct РаботаАгентаFUM: Codable, Equatable, Sendable {
    public let идентификатор: String
    public let владелец: String
    public let версияНазначения: UInt64
    public let цель: String
    public let вид: ВидРаботыАгентаFUM
    public let описание: String
    public let назначивший: СсылкаАгентаFUM
    public let ожидаемыйПотребитель: СсылкаАгентаFUM
    public let ссылкаНазначения: ЗакреплённаяСсылка
    public let происхождение: [ЗакреплённаяСсылка]

    public init(идентификатор: String, владелец: String, версияНазначения: UInt64,
                цель: String, вид: ВидРаботыАгентаFUM, описание: String,
                назначивший: СсылкаАгентаFUM,
                ожидаемыйПотребитель: СсылкаАгентаFUM,
                ссылкаНазначения: ЗакреплённаяСсылка,
                происхождение: [ЗакреплённаяСсылка]) {
        self.идентификатор = идентификатор
        self.владелец = владелец
        self.версияНазначения = версияНазначения
        self.цель = цель
        self.вид = вид
        self.описание = описание
        self.назначивший = назначивший
        self.ожидаемыйПотребитель = ожидаемыйПотребитель
        self.ссылкаНазначения = ссылкаНазначения
        self.происхождение = происхождение
    }

    fileprivate func проверить(для агента: ИдентичностьАгентаFUM) throws {
        guard ИдентичностьАгентаFUM.допустимыйИдентификатор(идентификатор),
              владелец == агента.идентификатор, версияНазначения > 0,
              !цель.isEmpty, цель.utf8.count <= 2048,
              !описание.isEmpty, описание.utf8.count <= 8192,
              назначивший == агента.ожидаемыйПотребитель,
              ожидаемыйПотребитель == агента.ожидаемыйПотребитель,
              ИдентичностьАгентаFUM.допустимаяСсылкаАгента(назначивший),
              ИдентичностьАгентаFUM.допустимаяСсылкаАгента(ожидаемыйПотребитель),
              Self.допустимаяСсылка(ссылкаНазначения),
              !происхождение.isEmpty, происхождение.count <= 8,
              происхождение.allSatisfy(Self.допустимаяСсылка) else {
            throw ОшибкаАгентаFUM.некорректнаяРабота
        }
    }

    private static func допустимаяСсылка(_ ссылка: ЗакреплённаяСсылка) -> Bool {
        !ссылка.адрес.isEmpty && ссылка.адрес.utf8.count <= 512 &&
            !ссылка.версия.isEmpty && ссылка.версия.utf8.count <= 128 &&
            ИдентичностьАгентаFUM.верныйSHA256(ссылка.sha256)
    }
}


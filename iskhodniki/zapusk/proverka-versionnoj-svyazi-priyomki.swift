import Foundation

public struct ОжидаемаяСвязьПриёмки: Equatable, Sendable {
    public let отклонённыйКоммит: String
    public let принятыйКоммит: String
    public let принятоеДерево: String

    public init(
        отклонённыйКоммит: String,
        принятыйКоммит: String,
        принятоеДерево: String
    ) {
        self.отклонённыйКоммит = отклонённыйКоммит
        self.принятыйКоммит = принятыйКоммит
        self.принятоеДерево = принятоеДерево
    }
}

public struct ПринятаяВерсияКомпозиции: Equatable, Sendable {
    public let коммит: String
    public let дерево: String
    public let родитель: String
    public let заменяет: String
    public let уровень: String

}

public enum ОшибкаСвязиПриёмки: Error, Equatable, Sendable {
    case неверныйДокумент
}

public enum ПроверкаСвязиПриёмкиКомпозиции {
    public static func принять(
        _ данные: Data,
        ожидается: ОжидаемаяСвязьПриёмки
    ) throws -> ПринятаяВерсияКомпозиции {
        let документ: ДокументСвязи
        do {
            документ = try JSONDecoder().decode(ДокументСвязи.self, from: данные)
        } catch {
            throw ОшибкаСвязиПриёмки.неверныйДокумент
        }

        let коррекция = документ.следующееНазначение.добавочнаяКоррекция
        let поставка = коррекция.исправленнаяПоставка
        let связь = документ.связьПриёмки
        let отклонённый = связь.отклонённыйИсточник
        let принятый = связь.принятаяВерсия

        guard документ.версия == 2,
              документ.исправлениеМетки.исправленоВВерсии == документ.версия,
              связь.схема == "fum.связь-приёмки-поставки.1",
              связь.уровень == "потребитель-FUMA",
              поставка.уровеньПриёмки == "потребитель-FUMA",
              !связь.корневаяПриёмка,
              !связь.интеграцияВОсновнуюВетку,
              коррекция.источник == ожидается.отклонённыйКоммит,
              коррекция.получено,
              !коррекция.принято,
              отклонённый.коммит == ожидается.отклонённыйКоммит,
              !отклонённый.принято,
              принятый.коммит == ожидается.принятыйКоммит,
              принятый.дерево == ожидается.принятоеДерево,
              принятый.принято,
              поставка.коммит == ожидается.принятыйКоммит,
              поставка.дерево == ожидается.принятоеДерево,
              поставка.получено,
              поставка.принято,
              принятый.коммит == поставка.коммит,
              принятый.дерево == поставка.дерево,
              принятый.родитель == поставка.родитель,
              принятый.родитель == ожидается.отклонённыйКоммит,
              принятый.заменяет == ожидается.отклонённыйКоммит,
              поставка.родитель == ожидается.отклонённыйКоммит,
              поставка.заменяетОтклонённыйИсточник == ожидается.отклонённыйКоммит,
              принятый.коммит != ожидается.отклонённыйКоммит else {
            throw ОшибкаСвязиПриёмки.неверныйДокумент
        }

        return ПринятаяВерсияКомпозиции(
            коммит: принятый.коммит,
            дерево: принятый.дерево,
            родитель: принятый.родитель,
            заменяет: принятый.заменяет,
            уровень: связь.уровень)
    }
}

private struct ДокументСвязи: Decodable {
    let версия: Int
    let исправлениеМетки: ИсправлениеМетки
    let следующееНазначение: СледующееНазначение
    let связьПриёмки: СвязьПриёмки

    enum CodingKeys: String, CodingKey {
        case версия
        case исправлениеМетки = "исправление_метки_приёмки"
        case следующееНазначение = "следующее_назначение_чистой_композиции"
        case связьПриёмки = "связь_приёмки_композиции"
    }
}

private struct ИсправлениеМетки: Decodable {
    let исправленоВВерсии: Int

    enum CodingKeys: String, CodingKey {
        case исправленоВВерсии = "исправлено_в_версии"
    }
}

private struct СледующееНазначение: Decodable {
    let добавочнаяКоррекция: ДобавочнаяКоррекция

    enum CodingKeys: String, CodingKey {
        case добавочнаяКоррекция = "добавочная_коррекция"
    }
}

private struct ДобавочнаяКоррекция: Decodable {
    let источник: String
    let получено: Bool
    let принято: Bool
    let исправленнаяПоставка: ИсправленнаяПоставка

    enum CodingKeys: String, CodingKey {
        case источник = "C"
        case получено
        case принято
        case исправленнаяПоставка = "исправленная_поставка"
    }
}

private struct ИсправленнаяПоставка: Decodable {
    let коммит: String
    let дерево: String
    let родитель: String
    let получено: Bool
    let принято: Bool
    let уровеньПриёмки: String
    let заменяетОтклонённыйИсточник: String

    enum CodingKeys: String, CodingKey {
        case коммит
        case дерево
        case родитель
        case получено
        case принято
        case уровеньПриёмки = "уровень_приёмки"
        case заменяетОтклонённыйИсточник = "заменяет_отклонённый_источник"
    }
}

private struct СвязьПриёмки: Decodable {
    let схема: String
    let уровень: String
    let отклонённыйИсточник: ОтклонённаяВерсия
    let принятаяВерсия: ПринятаяВерсия
    let корневаяПриёмка: Bool
    let интеграцияВОсновнуюВетку: Bool

    enum CodingKeys: String, CodingKey {
        case схема
        case уровень
        case отклонённыйИсточник = "отклонённый_источник"
        case принятаяВерсия = "принятая_версия"
        case корневаяПриёмка = "ROOT_приёмка"
        case интеграцияВОсновнуюВетку = "master_интеграция"
    }
}

private struct ОтклонённаяВерсия: Decodable {
    let коммит: String
    let принято: Bool
}

private struct ПринятаяВерсия: Decodable {
    let коммит: String
    let дерево: String
    let родитель: String
    let принято: Bool
    let заменяет: String
}

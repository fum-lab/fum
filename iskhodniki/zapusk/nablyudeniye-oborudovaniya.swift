public struct СнимокНаблюденийОборудования: Codable, Equatable, Sendable {
    public let схема: String
    public let статические: [МетрикаНаблюденияОборудования]
    public let динамические: [МетрикаНаблюденияОборудования]
    public let покрытие: ПокрытиеНаблюденияОборудования

    public init(
        схема: String = "fum.наблюдение-оборудования.1",
        статические: [МетрикаНаблюденияОборудования],
        динамические: [МетрикаНаблюденияОборудования],
        покрытие: ПокрытиеНаблюденияОборудования
    ) {
        self.схема = схема
        self.статические = статические
        self.динамические = динамические
        self.покрытие = покрытие
    }

    public func проверить() throws {
        guard схема == "fum.наблюдение-оборудования.1" else {
            throw ОшибкаНаблюденияОборудования.невернаяСхема
        }
        let именаСтатических: [ИмяПараметраОборудования] = [
            .версияОперационнойСистемы,
            .числоПроцессорныхЯдер,
            .физическаяПамять
        ]
        let именаДинамических: [ИмяПараметраОборудования] = [
            .активныеПроцессорныеЯдра,
            .тепловоеСостояние,
            .температура,
            .загрузкаПроцессора
        ]
        guard статические.map(\.имя) == именаСтатических,
              динамические.map(\.имя) == именаДинамических else {
            throw ОшибкаНаблюденияОборудования.неверныйСоставПараметров
        }
        guard покрытие.неизвестныеПараметры == [.температура, .загрузкаПроцессора],
              Set(покрытие.неизвестныеПараметры).count == покрытие.неизвестныеПараметры.count else {
            throw ОшибкаНаблюденияОборудования.неверноеПокрытие
        }
        try статические.forEach { try Self.проверить($0) }
        try динамические.forEach { try Self.проверить($0) }

        if case .доступно(.целое(let общееЧислоЯдер)) = статические[1].результат,
           case .доступно(.целое(let активныеЯдра)) = динамические[0].результат,
           активныеЯдра > общееЧислоЯдер {
            throw ОшибкаНаблюденияОборудования.неверноеЗначение
        }
        for параметр in [динамические[2], динамические[3]] {
            guard параметр.результат.состояние == .неизвестно,
                  параметр.результат.значение == nil else {
                throw ОшибкаНаблюденияОборудования.неверноеПокрытие
            }
        }
    }

    public func форматированныеJSON() throws -> Data {
        try проверить()
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        var данные = try encoder.encode(self)
        if данные.last != 0x0A { данные.append(0x0A) }
        return данные
    }

    private static func проверить(_ метрика: МетрикаНаблюденияОборудования) throws {
        guard !метрика.источник.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw ОшибкаНаблюденияОборудования.неверныйИсточник
        }
        guard Self.дата(метрика.окно.начало) != nil,
              let окончание = Self.дата(метрика.окно.окончание),
              let начало = Self.дата(метрика.окно.начало),
              начало <= окончание else {
            throw ОшибкаНаблюденияОборудования.неверноеОкно
        }
        let ожидаемаяЕдиница: ЕдиницаИзмеренияОборудования
        switch метрика.имя {
        case .версияОперационнойСистемы: ожидаемаяЕдиница = .версия
        case .числоПроцессорныхЯдер, .активныеПроцессорныеЯдра: ожидаемаяЕдиница = .ядро
        case .физическаяПамять: ожидаемаяЕдиница = .байт
        case .тепловоеСостояние: ожидаемаяЕдиница = .категория
        case .температура: ожидаемаяЕдиница = .градусЦельсия
        case .загрузкаПроцессора: ожидаемаяЕдиница = .процент
        }
        guard метрика.единица == ожидаемаяЕдиница else {
            throw ОшибкаНаблюденияОборудования.невернаяЕдиница
        }
        switch (метрика.имя, метрика.результат) {
        case (.версияОперационнойСистемы, .доступно(.версия(let версия))):
            guard версия.основная >= 0, версия.дополнительная >= 0, версия.исправление >= 0 else {
                throw ОшибкаНаблюденияОборудования.неверноеЗначение
            }
        case (.числоПроцессорныхЯдер, .доступно(.целое(let число))),
             (.физическаяПамять, .доступно(.целое(let число))),
             (.активныеПроцессорныеЯдра, .доступно(.целое(let число))):
            guard число > 0 else { throw ОшибкаНаблюденияОборудования.неверноеЗначение }
        case (.тепловоеСостояние, .доступно(.тепловойРежим)):
            break
        case (.температура, .неизвестно(let причина)),
             (.загрузкаПроцессора, .неизвестно(let причина)):
            guard !причина.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                throw ОшибкаНаблюденияОборудования.неверноеЗначение
            }
        case (_, .недоступно(let причина)), (_, .неизвестно(let причина)):
            guard !причина.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                throw ОшибкаНаблюденияОборудования.неверноеЗначение
            }
        default:
            throw ОшибкаНаблюденияОборудования.неверноеЗначение
        }
    }

    private static func дата(_ строка: String) -> Date? {
        let дробныйФорматтер = ISO8601DateFormatter()
        дробныйФорматтер.timeZone = TimeZone(secondsFromGMT: 0)
        дробныйФорматтер.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        if let дата = дробныйФорматтер.date(from: строка) { return дата }
        let обычныйФорматтер = ISO8601DateFormatter()
        обычныйФорматтер.timeZone = TimeZone(secondsFromGMT: 0)
        обычныйФорматтер.formatOptions = [.withInternetDateTime]
        return обычныйФорматтер.date(from: строка)
    }
}

public struct СырыеСведенияОборудования: Sendable {
    public let версияОС: Результат<ВерсияОС>
    public let числоЯдер: Результат<Int>
    public let физическаяПамятьБайтов: Результат<UInt64>
    public let активныеЯдра: Результат<Int>
    public let тепловойРежим: Результат<ТепловойРежим>

    public init(
        версияОС: Результат<ВерсияОС>,
        числоЯдер: Результат<Int>,
        физическаяПамятьБайтов: Результат<UInt64>,
        активныеЯдра: Результат<Int>,
        тепловойРежим: Результат<ТепловойРежим>
    ) {
        self.версияОС = версияОС
        self.числоЯдер = числоЯдер
        self.физическаяПамятьБайтов = физическаяПамятьБайтов
        self.активныеЯдра = активныеЯдра
        self.тепловойРежим = тепловойРежим
    }
}

public protocol ИсточникНаблюденийОборудования: Sendable {
    func прочитать() -> СырыеСведенияОборудования
}

public struct СистемныйИсточникНаблюденийОборудования: ИсточникНаблюденийОборудования {
    public init() {}

    public func прочитать() -> СырыеСведенияОборудования {
        let сведения = ProcessInfo.processInfo
        let версия = сведения.operatingSystemVersion
        let режим: Результат<ТепловойРежим>
        switch сведения.thermalState {
        case .nominal: режим = .доступно(.номинальный)
        case .fair: режим = .доступно(.умеренный)
        case .serious: режим = .доступно(.серьёзный)
        case .critical: режим = .доступно(.критический)
        @unknown default: режим = .неизвестно("Система вернула неизвестный тепловой режим.")
        }
        return СырыеСведенияОборудования(
            версияОС: .доступно(ВерсияОС(
                основная: версия.majorVersion,
                дополнительная: версия.minorVersion,
                исправление: версия.patchVersion
            )),
            числоЯдер: .доступно(сведения.processorCount),
            физическаяПамятьБайтов: .доступно(сведения.physicalMemory),
            активныеЯдра: .доступно(сведения.activeProcessorCount),
            тепловойРежим: режим
        )
    }
}

public enum НаблюдательОборудования {
    private static let источникВерсии = "Foundation.ProcessInfo.operatingSystemVersion"
    private static let источникЯдер = "Foundation.ProcessInfo.processorCount"
    private static let источникПамяти = "Foundation.ProcessInfo.physicalMemory"
    private static let источникАктивныхЯдер = "Foundation.ProcessInfo.activeProcessorCount"
    private static let источникТепловогоРежима = "Foundation.ProcessInfo.thermalState"

    public static func собрать(
        из источник: any ИсточникНаблюденийОборудования,
        окно: ОкноНаблюдения
    ) throws -> СнимокНаблюденийОборудования {
        try собрать(данные: источник.прочитать(), окно: окно)
    }

    public static func снятьСейчас() throws -> СнимокНаблюденийОборудования {
        let часы = ContinuousClock()
        let началоМонотонно = часы.now
        let началоНастенное = Date()
        let данные = СистемныйИсточникНаблюденийОборудования().прочитать()
        let окончаниеМонотонно = часы.now
        let окончаниеНастенное = Date()
        let длительность = началоМонотонно.duration(to: окончаниеМонотонно).components
        let наносекунды = UInt64(max(0, длительность.seconds)) * 1_000_000_000
            + UInt64(max(0, длительность.attoseconds)) / 1_000_000_000
        let окно = ОкноНаблюдения(
            начало: Self.времяISO8601(началоНастенное),
            окончание: Self.времяISO8601(окончаниеНастенное),
            длительностьНаносекунд: наносекунды
        )
        return try собрать(данные: данные, окно: окно)
    }

    private static func собрать(
        данные: СырыеСведенияОборудования,
        окно: ОкноНаблюдения
    ) throws -> СнимокНаблюденийОборудования {
        let общееЧислоЯдер = число(данные.числоЯдер)
        let пределАктивныхЯдер: UInt64?
        if case .доступно(.целое(let значение)) = общееЧислоЯдер {
            пределАктивныхЯдер = значение
        } else {
            пределАктивныхЯдер = nil
        }
        let активныеЯдра = число(данные.активныеЯдра, неБольшеЧем: пределАктивныхЯдер)
        let снимок = СнимокНаблюденийОборудования(
            статические: [
                МетрикаНаблюденияОборудования(
                    имя: .версияОперационнойСистемы,
                    единица: .версия,
                    источник: источникВерсии,
                    окно: окно,
                    результат: версия(данные.версияОС)
                ),
                МетрикаНаблюденияОборудования(
                    имя: .числоПроцессорныхЯдер,
                    единица: .ядро,
                    источник: источникЯдер,
                    окно: окно,
                    результат: общееЧислоЯдер
                ),
                МетрикаНаблюденияОборудования(
                    имя: .физическаяПамять,
                    единица: .байт,
                    источник: источникПамяти,
                    окно: окно,
                    результат: память(данные.физическаяПамятьБайтов)
                )
            ],
            динамические: [
                МетрикаНаблюденияОборудования(
                    имя: .активныеПроцессорныеЯдра,
                    единица: .ядро,
                    источник: источникАктивныхЯдер,
                    окно: окно,
                    результат: активныеЯдра
                ),
                МетрикаНаблюденияОборудования(
                    имя: .тепловоеСостояние,
                    единица: .категория,
                    источник: источникТепловогоРежима,
                    окно: окно,
                    результат: режим(данные.тепловойРежим)
                ),
                МетрикаНаблюденияОборудования(
                    имя: .температура,
                    единица: .градусЦельсия,
                    источник: "не-запрашивался",
                    окно: окно,
                    результат: .неизвестно("Температура не измерялась в этом срезе.")
                ),
                МетрикаНаблюденияОборудования(
                    имя: .загрузкаПроцессора,
                    единица: .процент,
                    источник: "не-запрашивался",
                    окно: окно,
                    результат: .неизвестно("Процент загрузки не измерялся в этом срезе.")
                )
            ],
            покрытие: ПокрытиеНаблюденияОборудования(
                неизвестныеПараметры: [.температура, .загрузкаПроцессора],
                ограничения: [
                    "Активные процессорные ядра не являются процентом загрузки процессора.",
                    "Тепловой режим системы не является прямым измерением температуры."
                ]
            )
        )
        try снимок.проверить()
        return снимок
    }

    private static func версия(_ результат: Результат<ВерсияОС>) -> Результат<ЗначениеПараметраОборудования> {
        switch результат {
        case .доступно(let версия):
            guard версия.основная >= 0, версия.дополнительная >= 0, версия.исправление >= 0 else {
                return .неизвестно("Источник вернул некорректные компоненты версии ОС.")
            }
            return .доступно(.версия(версия))
        case .недоступно(let причина): return .недоступно(причина)
        case .неизвестно(let причина): return .неизвестно(причина)
        }
    }

    private static func число(
        _ результат: Результат<Int>,
        неБольшеЧем предел: UInt64? = nil
    ) -> Результат<ЗначениеПараметраОборудования> {
        switch результат {
        case .доступно(let значение):
            guard значение > 0 else { return .неизвестно("Источник вернул неположительное число.") }
            let целое = UInt64(значение)
            if let предел, целое > предел {
                return .неизвестно("Число активных ядер вышло за объявленную границу.")
            }
            return .доступно(.целое(целое))
        case .недоступно(let причина): return .недоступно(причина)
        case .неизвестно(let причина): return .неизвестно(причина)
        }
    }

    private static func память(_ результат: Результат<UInt64>) -> Результат<ЗначениеПараметраОборудования> {
        switch результат {
        case .доступно(let значение):
            guard значение > 0 else { return .неизвестно("Источник вернул неположительный объём памяти.") }
            return .доступно(.целое(значение))
        case .недоступно(let причина): return .недоступно(причина)
        case .неизвестно(let причина): return .неизвестно(причина)
        }
    }

    private static func режим(
        _ результат: Результат<ТепловойРежим>
    ) -> Результат<ЗначениеПараметраОборудования> {
        switch результат {
        case .доступно(let режим): return .доступно(.тепловойРежим(режим))
        case .недоступно(let причина): return .недоступно(причина)
        case .неизвестно(let причина): return .неизвестно(причина)
        }
    }

    private static func времяISO8601(_ время: Date) -> String {
        let форматтер = ISO8601DateFormatter()
        форматтер.timeZone = TimeZone(secondsFromGMT: 0)
        форматтер.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        return форматтер.string(from: время)
    }

public enum ЗначениеПараметраОборудования: Codable, Equatable, Sendable {
    case версия(ВерсияОС)
    case целое(UInt64)
    case тепловойРежим(ТепловойРежим)

    private enum Ключ: String, CodingKey {
        case вид
        case данные
    }

    private enum Вид: String, Codable {
        case версия
        case целое
        case тепловойРежим = "тепловой_режим"
    }

    public init(from decoder: any Decoder) throws {
        let контейнер = try decoder.container(keyedBy: Ключ.self)
        switch try контейнер.decode(Вид.self, forKey: .вид) {
        case .версия:
            self = .версия(try контейнер.decode(ВерсияОС.self, forKey: .данные))
        case .целое:
            self = .целое(try контейнер.decode(UInt64.self, forKey: .данные))
        case .тепловойРежим:
            self = .тепловойРежим(try контейнер.decode(ТепловойРежим.self, forKey: .данные))
        }
    }

    public func encode(to encoder: any Encoder) throws {
        var контейнер = encoder.container(keyedBy: Ключ.self)
        switch self {
        case .версия(let версия):
            try контейнер.encode(Вид.версия, forKey: .вид)
            try контейнер.encode(версия, forKey: .данные)
        case .целое(let значение):
            try контейнер.encode(Вид.целое, forKey: .вид)
            try контейнер.encode(значение, forKey: .данные)
        case .тепловойРежим(let режим):
            try контейнер.encode(Вид.тепловойРежим, forKey: .вид)
            try контейнер.encode(режим, forKey: .данные)
        }
    }
}


import Foundation

public enum СостояниеНаблюдения: String, Codable, Equatable, Sendable {
    case доступно = "AVAILABLE"
    case недоступно = "UNAVAILABLE"
    case неизвестно = "UNKNOWN"
}

public enum Результат<Значение: Codable & Equatable & Sendable>: Codable, Equatable, Sendable {
    case доступно(Значение)
    case недоступно(String)
    case неизвестно(String)

    private enum Ключ: String, CodingKey {
        case состояние
        case значение
        case причина
    }

    public var состояние: СостояниеНаблюдения {
        switch self {
        case .доступно: .доступно
        case .недоступно: .недоступно
        case .неизвестно: .неизвестно
        }
    }

    public var значение: Значение? {
        guard case .доступно(let значение) = self else { return nil }
        return значение
    }

    public init(from decoder: any Decoder) throws {
        let контейнер = try decoder.container(keyedBy: Ключ.self)
        let состояние = try контейнер.decode(СостояниеНаблюдения.self, forKey: .состояние)
        switch состояние {
        case .доступно:
            let значение = try контейнер.decode(Значение.self, forKey: .значение)
            self = .доступно(значение)
        case .недоступно, .неизвестно:
            if контейнер.contains(.значение), try !контейнер.decodeNil(forKey: .значение) {
                throw DecodingError.dataCorruptedError(
                    forKey: .значение,
                    in: контейнер,
                    debugDescription: "Значение для состояния без наблюдаемого результата должно отсутствовать."
                )
            }
            let причина = try контейнер.decode(String.self, forKey: .причина)
            guard !причина.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                throw DecodingError.dataCorruptedError(
                    forKey: .причина,
                    in: контейнер,
                    debugDescription: "Причина неизвестного или недоступного значения не может быть пустой."
                )
            }
            if состояние == .недоступно {
                self = .недоступно(причина)
            } else {
                self = .неизвестно(причина)
            }
        }
    }

    public func encode(to encoder: any Encoder) throws {
        var контейнер = encoder.container(keyedBy: Ключ.self)
        try контейнер.encode(состояние, forKey: .состояние)
        switch self {
        case .доступно(let значение):
            try контейнер.encode(значение, forKey: .значение)
        case .недоступно(let причина), .неизвестно(let причина):
            try контейнер.encode(причина, forKey: .причина)
        }
    }
}


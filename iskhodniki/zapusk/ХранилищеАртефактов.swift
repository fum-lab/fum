public enum ВидПреемника: String, Codable, Sendable {
    case вопросОтвет
    case требование
}

public enum РольПроисхождения: String, Codable, Sendable {
    case вопрос
    case ответ
    case требование
}

public struct СсылкаПроисхождения: Codable, Equatable, Sendable {
    public let роль: РольПроисхождения
    public let адрес: String
    public let закреплённаяВерсия: String
    public let sha256: String

    public init(роль: РольПроисхождения, адрес: String,
                закреплённаяВерсия: String, sha256: String) {
        self.роль = роль
        self.адрес = адрес
        self.закреплённаяВерсия = закреплённаяВерсия
        self.sha256 = sha256
    }
}

public enum СостояниеПреемника: String, Codable, Sendable {
    case ожидает
    case завершено
    case неВыполнено
    case неизвестно
}

public struct АртефактПреемника<Содержимое: Codable & Equatable & Sendable>:
    Codable, Equatable, Sendable {
    public let идентификатор: String
    public let поколение: UInt64
    public let вид: ВидПреемника
    public let время: String
    public let назначениеПерехода: String
    public let содержимое: Содержимое
    public let происхождение: [СсылкаПроисхождения]
    public let состояние: СостояниеПреемника

    public init(идентификатор: String, поколение: UInt64, вид: ВидПреемника,
                время: String, назначениеПерехода: String,
                содержимое: Содержимое, происхождение: [СсылкаПроисхождения],
                состояние: СостояниеПреемника) {
        self.идентификатор = идентификатор
        self.поколение = поколение
        self.вид = вид
        self.время = время
        self.назначениеПерехода = назначениеПерехода
        self.содержимое = содержимое
        self.происхождение = происхождение
        self.состояние = состояние
    }
}

public enum ИсходСохраненияПреемника: String, Codable, Sendable {
    case добавлен
    case точныйПовтор
}

public enum РезультатСохраненияПреемника<Содержимое: Codable & Equatable & Sendable>:
    Equatable, Sendable {
    case подтверждён(артефакт: АртефактПреемника<Содержимое>,
                     квитанция: Квитанция,
                     исход: ИсходСохраненияПреемника)
    /// Текущий вызов не повторяет запись; до нового решения нужна сверка только для чтения.
    case исходНеизвестен(идентификаторЗаписи: String, sha256: String)
}

public struct ВосстановленныйПреемник<Содержимое: Codable & Equatable & Sendable>:
    Equatable, Sendable {
    public let артефакт: АртефактПреемника<Содержимое>
    public let квитанция: Квитанция
    fileprivate let байтыЗаписи: Data
}

public enum ОшибкаХранилищаАртефактов: Error, Equatable, Sendable {
    case некорректныйАртефакт
    case недопустимыйПуть
    case неполныйХвост
    /// Тот же id/generation с другими входами или назначением удерживается без второго результата.
    case конфликтИдентификатора
    case занято
    case предел
    case нетЗаписи
    case повреждение
    case кодирование
    case системнаяОшибка(Int32)
}

/// Добавляет типизированный преемник через существующий сегмент без перезаписи истории.
/// Корень должен быть заранее создан и устойчиво синхронизирован вызывающей стороной.
/// Каждый вызов использует одного писателя и подтверждает результат новым чтением.
public struct ХранилищеАртефактов: Sendable {
    private let кореньХранилища: String
    private let операции: ФайловыеОперации

    public init(кореньХранилища: String) {
        self.кореньХранилища = кореньХранилища
        операции = .системные
    }

    init(кореньХранилища: String, операции: ФайловыеОперации) {
        self.кореньХранилища = кореньХранилища
        self.операции = операции
    }

    /// Отсутствующий или недолговечный корень не создаётся этой операцией.
    func сохранитьПреемника<Содержимое: Codable & Equatable & Sendable>(
        _ артефакт: АртефактПреемника<Содержимое>) throws
        -> РезультатСохраненияПреемника<Содержимое> {
        try проверить(артефакт)
        let байты: Data
        do { байты = try каноническиКодировать(артефакт) }
        catch { throw ОшибкаХранилищаАртефактов.кодирование }
        guard байты.count <= Int(Пределы.объект) else {
            throw ОшибкаХранилищаАртефактов.предел
        }

        let (описание, _, идентификаторЗаписи) = try описаниеЗаписи(
            идентификатор: артефакт.идентификатор,
            поколение: артефакт.поколение,
            время: артефакт.время)
        let корень: URL
        do { корень = try проверитьСуществующийКорень(кореньХранилища) }
        catch { throw ОшибкаХранилищаАртефактов.недопустимыйПуть }

        let писатель: Сегмент
        do {
            писатель = try Сегмент(кореньДанных: корень, запись: true, создать: true,
                                   операции: операции)
        } catch let ошибка as ОшибкаКонтейнера {
            if case .система = ошибка {
                return .исходНеизвестен(идентификаторЗаписи: идентификаторЗаписи,
                                        sha256: хэшСтрокой(байты))
            }
            throw перевести(ошибка)
        } catch {
            throw ОшибкаХранилищаАртефактов.недопустимыйПуть
        }
        defer { писатель.закрыть() }

        guard !писатель.естьХвост else { throw ОшибкаХранилищаАртефактов.неполныйХвост }
        let предыдущаяКвитанция: Квитанция?
        do { предыдущаяКвитанция = try писатель.квитанция(идентификаторЗаписи) }
        catch ОшибкаКонтейнера.нетЗаписи { предыдущаяКвитанция = nil }
        catch let ошибка as ОшибкаКонтейнера { throw перевести(ошибка) }

        var байтыЗаписи = байты
        if let предыдущаяКвитанция {
            guard предыдущаяКвитанция.описание == описание else {
                throw ОшибкаХранилищаАртефактов.конфликтИдентификатора
            }
            let сохранённыеБайты: Data
            do { сохранённыеБайты = try писатель.извлечь(идентификаторЗаписи) }
            catch let ошибка as ОшибкаКонтейнера { throw перевести(ошибка) }
            guard предыдущаяКвитанция.размер == UInt64(сохранённыеБайты.count),
                  предыдущаяКвитанция.хэш == хэшСтрокой(сохранённыеБайты) else {
                throw ОшибкаХранилищаАртефактов.повреждение
            }
            let заголовок: ЗаголовокПреемника
            do {
                заголовок = try JSONDecoder().decode(ЗаголовокПреемника.self,
                                                     from: сохранённыеБайты)
            } catch {
                throw ОшибкаХранилищаАртефактов.повреждение
            }
            if заголовок.вид != артефакт.вид {
                try проверитьСохранённуюНагрузку(
                    сохранённыеБайты,
                    вид: заголовок.вид,
                    ожидаемыйИдентификатор: артефакт.идентификатор,
                    ожидаемоеПоколение: артефакт.поколение,
                    ожидаемоеВремя: артефакт.время)
                throw ОшибкаХранилищаАртефактов.конфликтИдентификатора
            }
            let сохранённыйАртефакт: АртефактПреемника<Содержимое>
            do {
                сохранённыйАртефакт = try JSONDecoder().decode(
                    АртефактПреемника<Содержимое>.self, from: сохранённыеБайты)
            } catch {
                throw ОшибкаХранилищаАртефактов.повреждение
            }
            try проверитьСохранённыйАртефакт(
                сохранённыйАртефакт,
                ожидаемыйИдентификатор: артефакт.идентификатор,
                ожидаемоеПоколение: артефакт.поколение,
                ожидаемоеВремя: артефакт.время)
            guard сохранённыйАртефакт == артефакт else {
                throw ОшибкаХранилищаАртефактов.конфликтИдентификатора
            }
            байтыЗаписи = сохранённыеБайты
        }

        let квитанция: Квитанция
        do { квитанция = try писатель.добавить(описание, данные: байтыЗаписи) }
        catch let ошибка as ОшибкаКонтейнера {
            if case .система = ошибка {
                return .исходНеизвестен(идентификаторЗаписи: идентификаторЗаписи,
                                        sha256: хэшСтрокой(байтыЗаписи))
            }
            throw перевести(ошибка)
        } catch {
            return .исходНеизвестен(идентификаторЗаписи: идентификаторЗаписи,
                                    sha256: хэшСтрокой(байтыЗаписи))
        }

        писатель.закрыть()
        do {
            guard let переоткрытый = try восстановитьПреемника(
                идентификатор: артефакт.идентификатор,
                поколение: артефакт.поколение,
                как: Содержимое.self),
                  переоткрытый.артефакт == артефакт,
                  переоткрытый.квитанция == квитанция,
                  переоткрытый.байтыЗаписи == байтыЗаписи else {
                return .исходНеизвестен(идентификаторЗаписи: идентификаторЗаписи,
                                        sha256: хэшСтрокой(байтыЗаписи))
            }
            return .подтверждён(артефакт: переоткрытый.артефакт,
                                квитанция: переоткрытый.квитанция,
                                исход: предыдущаяКвитанция == nil ? .добавлен : .точныйПовтор)
        } catch {
            return .исходНеизвестен(идентификаторЗаписи: идентификаторЗаписи,
                                    sha256: хэшСтрокой(байтыЗаписи))
        }
    }

    /// Сверяет запись только для чтения. Неполный хвост блокирует восстановление без ремонта.
    public func восстановитьПреемника<Содержимое: Codable & Equatable & Sendable>(
        идентификатор: String,
        поколение: UInt64,
        как _: Содержимое.Type) throws -> ВосстановленныйПреемник<Содержимое>? {
        guard !идентификатор.isEmpty, идентификатор.utf8.count <= 256,
              !идентификатор.utf8.contains(0), поколение > 0 else {
            throw ОшибкаХранилищаАртефактов.некорректныйАртефакт
        }
        let (_, байтыКлюча, идентификаторЗаписи) = try описаниеЗаписи(
            идентификатор: идентификатор, поколение: поколение, время: "восстановление")
        let корень: URL
        do { корень = try проверитьСуществующийКорень(кореньХранилища) }
        catch { throw ОшибкаХранилищаАртефактов.недопустимыйПуть }

        let читатель: Сегмент
        do {
            читатель = try Сегмент(кореньДанных: корень, запись: false, создать: false,
                                   операции: операции)
        } catch let ошибка as ОшибкаКонтейнера {
            throw перевести(ошибка)
        } catch {
            throw ОшибкаХранилищаАртефактов.недопустимыйПуть
        }
        defer { читатель.закрыть() }
        guard !читатель.естьХвост else { throw ОшибкаХранилищаАртефактов.неполныйХвост }

        let квитанция: Квитанция
        do { квитанция = try читатель.квитанция(идентификаторЗаписи) }
        catch ОшибкаКонтейнера.нетЗаписи { return nil }
        catch let ошибка as ОшибкаКонтейнера { throw перевести(ошибка) }

        guard квитанция.описание.идентификатор == идентификаторЗаписи,
              квитанция.описание.тип == Self.типЗаписи,
              квитанция.описание.версияСхемы == 1,
              квитанция.описание.источник == Self.источникЗаписи,
              квитанция.описание.спецификация == байтыКлюча else {
            throw ОшибкаХранилищаАртефактов.повреждение
        }
        let байты: Data
        do { байты = try читатель.извлечь(идентификаторЗаписи) }
        catch let ошибка as ОшибкаКонтейнера { throw перевести(ошибка) }
        guard квитанция.размер == UInt64(байты.count),
              квитанция.хэш == хэшСтрокой(байты) else {
            throw ОшибкаХранилищаАртефактов.повреждение
        }
        let артефакт: АртефактПреемника<Содержимое>
        do { артефакт = try JSONDecoder().decode(АртефактПреемника<Содержимое>.self, from: байты) }
        catch { throw ОшибкаХранилищаАртефактов.повреждение }

        try проверить(артефакт)
        guard артефакт.идентификатор == идентификатор,
              артефакт.поколение == поколение,
              артефакт.время == квитанция.описание.время else {
            throw ОшибкаХранилищаАртефактов.повреждение
        }
        return ВосстановленныйПреемник(артефакт: артефакт,
                                      квитанция: квитанция,
                                      байтыЗаписи: байты)
    }

    private static let типЗаписи = "преемник-артефакт-a12"
    private static let источникЗаписи = "fuma-a12"

    /// Проверяет существующий корень через openat/O_NOFOLLOW, не создавая компоненты пути.
    /// Проверка находится в этом source-файле, чтобы чистый HEAD не зависел от локальной правки
    /// ПутьХранилища. После проверки Segment ещё раз безопасно открывает путь по собственному API.
    private func проверитьСуществующийКорень(_ путь: String) throws -> URL {
        let части = путь.split(separator: "/", omittingEmptySubsequences: false)
        guard путь.hasPrefix("/"), !путь.utf8.contains(0), части.count > 1,
              части.dropFirst().allSatisfy({ !$0.isEmpty && $0 != "." && $0 != ".." }) else {
            throw ОшибкаХранилищаАртефактов.недопустимыйПуть
        }
        var дескриптор = Darwin.open("/", O_RDONLY | O_DIRECTORY | O_CLOEXEC)
        guard дескриптор >= 0 else {
            throw ОшибкаХранилищаАртефактов.системнаяОшибка(errno)
        }
        defer { if дескриптор >= 0 { _ = Darwin.close(дескриптор) } }

        for часть in части.dropFirst() {
            try проверитьКаталогНеGit(дескриптор)
            guard часть != ".git" else { throw ОшибкаХранилищаАртефактов.недопустимыйПуть }
            let следующий = openat(
                дескриптор, String(часть), O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            guard следующий >= 0 else {
                let код = errno
                if код == ENOENT || код == ELOOP || код == ENOTDIR {
                    throw ОшибкаХранилищаАртефактов.недопустимыйПуть
                }
                throw ОшибкаХранилищаАртефактов.системнаяОшибка(код)
            }
            var сведения = stat()
            guard fstat(следующий, &сведения) == 0 else {
                let код = errno
                _ = Darwin.close(следующий)
                throw ОшибкаХранилищаАртефактов.системнаяОшибка(код)
            }
            guard сведения.st_mode & S_IFMT == S_IFDIR else {
                _ = Darwin.close(следующий)
                throw ОшибкаХранилищаАртефактов.недопустимыйПуть
            }
            _ = Darwin.close(дескриптор)
            дескриптор = следующий
        }

        try проверитьКаталогНеGit(дескриптор)
        var сведения = stat()
        guard fstat(дескриптор, &сведения) == 0 else {
            throw ОшибкаХранилищаАртефактов.системнаяОшибка(errno)
        }
        guard сведения.st_uid == geteuid(), сведения.st_mode & 0o7777 == 0o700 else {
            throw ОшибкаХранилищаАртефактов.недопустимыйПуть
        }
        return URL(fileURLWithPath: путь, isDirectory: true)
    }

    private func проверитьКаталогНеGit(_ дескриптор: Int32) throws {
        var сведения = stat()
        if fstatat(дескриптор, ".git", &сведения, AT_SYMLINK_NOFOLLOW) == 0 {
            throw ОшибкаХранилищаАртефактов.недопустимыйПуть
        }
        let ошибкаМаркера = errno
        guard ошибкаМаркера == ENOENT else {
            throw ОшибкаХранилищаАртефактов.системнаяОшибка(ошибкаМаркера)
        }
        let признаки = ["HEAD", "objects", "refs"]
        var найдено = 0
        for признак in признаки {
            if fstatat(дескриптор, признак, &сведения, AT_SYMLINK_NOFOLLOW) == 0 {
                найдено += 1
            } else {
                let код = errno
                guard код == ENOENT else {
                    throw ОшибкаХранилищаАртефактов.системнаяОшибка(код)
                }
            }
        }
        guard найдено < 2 else {
            throw ОшибкаХранилищаАртефактов.недопустимыйПуть
        }
    }

    private func описаниеЗаписи(идентификатор: String, поколение: UInt64,
                                время: String) throws -> (ОписаниеНаблюдения, Data, String) {
        let ключ = КлючЗаписи(идентификатор: идентификатор, поколение: поколение)
        let байтыКлюча: Data
        do { байтыКлюча = try каноническиКодировать(ключ) }
        catch { throw ОшибкаХранилищаАртефактов.кодирование }
        let идентификаторЗаписи = "a12-" + хэшСтрокой(байтыКлюча)
        let описание = ОписаниеНаблюдения(
            идентификатор: идентификаторЗаписи,
            тип: Self.типЗаписи,
            версияСхемы: 1,
            источник: Self.источникЗаписи,
            время: время,
            спецификация: байтыКлюча)
        return (описание, байтыКлюча, идентификаторЗаписи)
    }

    private func проверить<Содержимое: Codable & Equatable & Sendable>(
        _ артефакт: АртефактПреемника<Содержимое>) throws {
        guard !артефакт.идентификатор.isEmpty,
              артефакт.идентификатор.utf8.count <= 256,
              !артефакт.идентификатор.utf8.contains(0),
              артефакт.поколение > 0,
              !артефакт.назначениеПерехода.isEmpty,
              артефакт.назначениеПерехода.utf8.count <= 512,
              !артефакт.время.isEmpty,
              артефакт.время.utf8.count <= 128,
              !артефакт.происхождение.isEmpty,
              артефакт.происхождение.allSatisfy({
                  !$0.адрес.isEmpty && !$0.закреплённаяВерсия.isEmpty && Self.верныйSHA256($0.sha256)
              }) else {
            throw ОшибкаХранилищаАртефактов.некорректныйАртефакт
        }
        let ожидаемыеРоли: [РольПроисхождения]
        switch артефакт.вид {
        case .вопросОтвет: ожидаемыеРоли = [.вопрос, .ответ]
        case .требование: ожидаемыеРоли = [.требование]
        }
        guard артефакт.происхождение.map(\.роль) == ожидаемыеРоли else {
            throw ОшибкаХранилищаАртефактов.некорректныйАртефакт
        }
    }

    private func проверитьСохранённуюНагрузку(
        _ байты: Data,
        вид: ВидПреемника,
        ожидаемыйИдентификатор: String,
        ожидаемоеПоколение: UInt64,
        ожидаемоеВремя: String) throws {
        do {
            switch вид {
            case .вопросОтвет:
                let артефакт = try JSONDecoder().decode(
                    АртефактПреемника<НагрузкаВопросОтвета>.self, from: байты)
                try проверитьСохранённыйАртефакт(
                    артефакт,
                    ожидаемыйИдентификатор: ожидаемыйИдентификатор,
                    ожидаемоеПоколение: ожидаемоеПоколение,
                    ожидаемоеВремя: ожидаемоеВремя)
            case .требование:
                let артефакт = try JSONDecoder().decode(
                    АртефактПреемника<НагрузкаТребования>.self, from: байты)
                try проверитьСохранённыйАртефакт(
                    артефакт,
                    ожидаемыйИдентификатор: ожидаемыйИдентификатор,
                    ожидаемоеПоколение: ожидаемоеПоколение,
                    ожидаемоеВремя: ожидаемоеВремя)
            }
        } catch {
            throw ОшибкаХранилищаАртефактов.повреждение
        }
    }

    private func проверитьСохранённыйАртефакт<Содержимое: Codable & Equatable & Sendable>(
        _ артефакт: АртефактПреемника<Содержимое>,
        ожидаемыйИдентификатор: String,
        ожидаемоеПоколение: UInt64,
        ожидаемоеВремя: String) throws {
        do { try проверить(артефакт) }
        catch { throw ОшибкаХранилищаАртефактов.повреждение }
        guard артефакт.идентификатор == ожидаемыйИдентификатор,
              артефакт.поколение == ожидаемоеПоколение,
              артефакт.время == ожидаемоеВремя else {
            throw ОшибкаХранилищаАртефактов.повреждение
        }
    }

    private static func верныйSHA256(_ значение: String) -> Bool {
        let байты = Array(значение.utf8)
        return байты.count == 64 && байты.allSatisfy {
            (0x30...0x39).contains($0) || (0x61...0x66).contains($0)
        }
    }

    private func каноническиКодировать<Значение: Encodable>(_ значение: Значение) throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(значение)
    }

    private func перевести(_ ошибка: ОшибкаКонтейнера) -> ОшибкаХранилищаАртефактов {
        switch ошибка {
        case .система(let код): .системнаяОшибка(код)
        case .неполныйХвост: .неполныйХвост
        case .конфликтИдентификатора: .конфликтИдентификатора
        case .занят: .занято
        case .предел: .предел
        case .нетЗаписи: .нетЗаписи
        case .повреждение: .повреждение
        case .небезопасныйПуть: .недопустимыйПуть
        case .закрыт, .толькоЧтение: .повреждение
        }
    }

    private func хэшСтрокой(_ байты: Data) -> String {
        SHA256.hash(data: байты).map { String(format: "%02x", $0) }.joined()
    }
}

private struct КлючЗаписи: Codable, Equatable, Sendable {
    let идентификатор: String
    let поколение: UInt64
}


import Foundation
import Darwin
import КонтейнерНаблюдений
import МатериализацияУзлов

public enum РешениеАдресногоОтвета: String, Codable, Equatable, Sendable {
    case принятьИзвестныйРезультат
    case ждатьНовогоНаблюдения
    case наблюдатьНеизвестноеБезПовтора
}

public struct РезультатАдресногоОтвета: Codable, Sendable {
    public let operationID: String
    public let sha256СохранённогоСообщения: String
    public let решение: РешениеАдресногоОтвета
    public let следующийШагID: String?
}

private actor СостояниеЗаписиАдресногоОтвета {
    private(set) var состояние = СостояниеЗаписиСобытия.неНачата
    private(set) var квитанция: Квитанция?

    func подтверждена(_ значение: Квитанция) {
        квитанция = значение
        состояние = .подтверждена
    }
}

private struct РезультатСегментногоСохранения: Sendable {
    let квитанция: Квитанция
    let байтыПовторногоЧтения: Data
    let количествоЗаписей: Int
    let точныйПовтор: Bool
}

private struct ОшибкаСегментногоСохранения: Error, Sendable {
    let отказ: ОтказЗапуска
}

public actor ЦиклЗапуска {
    private let операции: ФайловыеОперации

    public init(операции: ФайловыеОперации = .системные) { self.операции = операции }

    /// Единственный Segment write/close/reopen/exact-readback путь для обоих lifecycle caller.
    nonisolated private static func сохранитьИПереоткрытьСегмент(
        путь: URL,
        идентификатор: String,
        данные: Data,
        операции: ФайловыеОперации,
        кодНеизвестнойОшибки: КодОтказаЗапуска,
        описаниеДля: (ОписаниеНаблюдения?) throws -> ОписаниеНаблюдения
    ) throws -> РезультатСегментногоСохранения {
        var состояние = СостояниеЗаписиСобытия.неНачата
        var квитанция: Квитанция?
        do {
            let писатель = try Сегмент(кореньДанных: путь, запись: true, создать: true, операции: операции)
            defer { писатель.закрыть() }
            guard !писатель.естьХвост else {
                throw ОтказЗапуска(код: .неполныйХвост,
                    сообщение: "Неполный хвост сохранён без восстановления.")
            }
            let прежняя = писатель.записи.first { $0.описание.идентификатор == идентификатор }
            let описание = try описаниеДля(прежняя?.описание)
            guard описание.идентификатор == идентификатор else {
                throw ОшибкаКонтейнера.конфликтИдентификатора
            }
            if let прежняя {
                guard описание == прежняя.описание,
                      try писатель.извлечь(идентификатор) == данные else {
                    throw ОшибкаКонтейнера.конфликтИдентификатора
                }
            }
            состояние = .исходНеизвестен
            let принятаяКвитанция = try писатель.добавить(описание, данные: данные)
            квитанция = принятаяКвитанция
            состояние = .подтверждена
            писатель.закрыть()

            let читатель = try Сегмент(кореньДанных: путь, запись: false, создать: false)
            defer { читатель.закрыть() }
            guard !читатель.естьХвост else {
                throw ОтказЗапуска(код: .неполныйХвост,
                    сообщение: "После сохранения обнаружен неполный хвост; восстановление не выполняется.")
            }
            let сохранённыеБайты = try читатель.извлечь(идентификатор)
            let прочитаннаяКвитанция = читатель.записи.first {
                $0.описание.идентификатор == идентификатор
            }
            guard сохранённыеБайты == данные,
                  прочитаннаяКвитанция == принятаяКвитанция else {
                throw ОтказЗапуска(код: .повреждениеИстории,
                    сообщение: "Повторное чтение не подтвердило точные байты и квитанцию.")
            }
            return РезультатСегментногоСохранения(
                квитанция: принятаяКвитанция, байтыПовторногоЧтения: сохранённыеБайты,
                количествоЗаписей: читатель.записи.count, точныйПовтор: прежняя != nil)
        } catch let ошибка as ОшибкаСегментногоСохранения {
            throw ошибка
        } catch {
            throw ОшибкаСегментногоСохранения(отказ: Self.отказСегментногоСохранения(
                ошибка, состояние: состояние, квитанция: квитанция,
                кодНеизвестнойОшибки: кодНеизвестнойОшибки))
        }
    }

    nonisolated private static func отказСегментногоСохранения(
        _ ошибка: Error,
        состояние: СостояниеЗаписиСобытия,
        квитанция: Квитанция?,
        кодНеизвестнойОшибки: КодОтказаЗапуска
    ) -> ОтказЗапуска {
        if let отказ = ошибка as? ОтказЗапуска {
            return ОтказЗапуска(код: отказ.код, сообщение: отказ.сообщение,
                системныйКод: отказ.системныйКод, записьСобытия: состояние,
                принятаяКвитанция: квитанция ?? отказ.принятаяКвитанция)
        }
        if let ошибка = ошибка as? ОшибкаКонтейнера {
            let код: КодОтказаЗапуска
            let системныйКод: Int32?
            switch ошибка {
            case .система(let значение):
                системныйКод = значение
                код = значение == ELOOP || значение == ENOTDIR ? .небезопасныйПуть : .системнаяОшибка
            case .повреждение: код = .повреждениеИстории; системныйКод = nil
            case .предел: код = .предел; системныйКод = nil
            case .неполныйХвост: код = .неполныйХвост; системныйКод = nil
            case .конфликтИдентификатора: код = .конфликтИдентификатора; системныйКод = nil
            case .занят: код = .хранилищеЗанято; системныйКод = nil
            case .небезопасныйПуть: код = .небезопасныйПуть; системныйКод = nil
            case .нетЗаписи, .закрыт, .толькоЧтение: код = .внутренняя; системныйКод = nil
            }
            return ОтказЗапуска(код: код, сообщение: String(describing: ошибка),
                системныйКод: системныйКод, записьСобытия: состояние, принятаяКвитанция: квитанция)
        }
        return ОтказЗапуска(код: кодНеизвестнойОшибки, сообщение: String(describing: ошибка),
            записьСобытия: состояние, принятаяКвитанция: квитанция)
    }

    /// Сначала долговечно сохраняет вход, затем использует только точные байты после reopen.
    /// Возвращает следующий шаг как данные; сам шаг или Native callback не запускает.
    public func сохранитьАдресныйОтвет(
        хранилище: String,
        дескриптор: ДескрипторЖизненногоЦиклаУзла,
        рабочийСписок: СвойРабочийСписокУзла,
        сообщение: ВходящееСообщениеЖизненногоЦикла
    ) async throws -> РезультатАдресногоОтвета {
        let состояние = СостояниеЗаписиАдресногоОтвета()
        let файловыеОперации = операции
        do {
            let подтверждение = try await рабочийСписок.подтвердитьСписокПослеСохранения(
                сообщение, дескриптор: дескриптор
            ) { запрос in
                let путь = try ПутьХранилища.подготовить(хранилище)
                let спецификация = Data("fum.lifecycle-message-persist.1".utf8)
                let сохранение = try Self.сохранитьИПереоткрытьСегмент(
                    путь: путь, идентификатор: запрос.operationID,
                    данные: запрос.каноническиеБайты, операции: файловыеОперации,
                    кодНеизвестнойОшибки: .аргументы
                ) { прежнее in
                    if let прежнее {
                        guard прежнее.тип == "входящее-сообщение-узла",
                              прежнее.версияСхемы == 1,
                              прежнее.источник == "fuma",
                              прежнее.спецификация == спецификация else {
                            throw ОшибкаКонтейнера.конфликтИдентификатора
                        }
                        return прежнее
                    }
                    let время = ISO8601DateFormatter()
                    время.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
                    время.timeZone = TimeZone(secondsFromGMT: 0)
                    return ОписаниеНаблюдения(
                        идентификатор: запрос.operationID, тип: "входящее-сообщение-узла",
                        версияСхемы: 1, источник: "fuma",
                        время: время.string(from: Date()), спецификация: спецификация)
                }
                await состояние.подтверждена(сохранение.квитанция)
                let конверт = try ЗапросСохраненияВходящегоСообщенияЖизненногоЦикла
                    .декодироватьСохранённыйКонверт(сохранение.байтыПовторногоЧтения)
                guard конверт.дескриптор == дескриптор,
                      конверт.рабочийСписок == рабочийСписок,
                      конверт.messageID == сообщение.messageID,
                      конверт.исходныеБайты == сообщение.исходныеБайты else {
                    throw ОтказЗапуска(код: .повреждениеИстории,
                        сообщение: "Декодированный сохранённый конверт расходится с адресным запросом.")
                }
                return КвитанцияПереоткрытияВходящегоСообщения(
                    operationID: запрос.operationID,
                    sha256Запроса: запрос.sha256КаноническихБайтов,
                    байтыПовторногоЧтения: сохранение.байтыПовторногоЧтения,
                    sha256ПовторногоЧтения: запрос.sha256КаноническихБайтов,
                    переоткрытыйРабочийСписок: конверт.рабочийСписок)
            }
            let свидетельство = try JSONDecoder().decode(
                СвидетельствоРезультатаДочернегоУзла.self, from: сообщение.исходныеБайты)
            let решение = try ПереходЖизненногоЦикла.решитьРезультатРодителю(
                свидетельство, дескриптор: дескриптор, рабочийСписок: подтверждение.рабочийСписок)
            switch решение {
            case .принятьИзвестныйРезультат(let следующийШагID):
                return РезультатАдресногоОтвета(
                    operationID: подтверждение.operationID,
                    sha256СохранённогоСообщения: подтверждение.sha256СохранённогоСообщения,
                    решение: .принятьИзвестныйРезультат, следующийШагID: следующийШагID)
            case .ждатьНовогоНаблюдения:
                return РезультатАдресногоОтвета(
                    operationID: подтверждение.operationID,
                    sha256СохранённогоСообщения: подтверждение.sha256СохранённогоСообщения,
                    решение: .ждатьНовогоНаблюдения, следующийШагID: nil)
            case .наблюдатьUnknownБезПовтора:
                return РезультатАдресногоОтвета(
                    operationID: подтверждение.operationID,
                    sha256СохранённогоСообщения: подтверждение.sha256СохранённогоСообщения,
                    решение: .наблюдатьНеизвестноеБезПовтора, следующийШагID: nil)
            }
        } catch let ошибка as ОтказЗапуска {
            throw await отказ(ошибка, состояние: состояние)
        } catch let ошибка as ОшибкаСегментногоСохранения {
            throw await отказ(ошибка.отказ, состояние: состояние)
        } catch let ошибка as ОшибкаКонтейнера {
            let код: КодОтказаЗапуска
            let системныйКод: Int32?
            switch ошибка {
            case .система(let значение):
                системныйКод = значение
                код = значение == ELOOP || значение == ENOTDIR ? .небезопасныйПуть : .системнаяОшибка
            case .повреждение: код = .повреждениеИстории; системныйКод = nil
            case .предел: код = .предел; системныйКод = nil
            case .неполныйХвост: код = .неполныйХвост; системныйКод = nil
            case .конфликтИдентификатора: код = .конфликтИдентификатора; системныйКод = nil
            case .занят: код = .хранилищеЗанято; системныйКод = nil
            case .небезопасныйПуть: код = .небезопасныйПуть; системныйКод = nil
            case .нетЗаписи, .закрыт, .толькоЧтение: код = .внутренняя; системныйКод = nil
            }
            throw await отказ(ОтказЗапуска(код: код, сообщение: String(describing: ошибка),
                системныйКод: системныйКод), состояние: состояние)
        } catch {
            throw await отказ(ОтказЗапуска(код: .аргументы, сообщение: "Адресный ответ не прошёл проверку."),
                состояние: состояние)
        }
    }

    private func отказ(
        _ ошибка: ОтказЗапуска,
        состояние: СостояниеЗаписиАдресногоОтвета
    ) async -> ОтказЗапуска {
        let запись = await состояние.состояние
        let квитанция = await состояние.квитанция
        return ОтказЗапуска(код: ошибка.код, сообщение: ошибка.сообщение,
            системныйКод: ошибка.системныйКод,
            записьСобытия: запись == .неНачата ? ошибка.записьСобытия : запись,
            принятаяКвитанция: квитанция ?? ошибка.принятаяКвитанция)
    }

    public func выполнить(_ параметры: ПараметрыЗапуска) throws -> РезультатЦикла {
        let часы = ContinuousClock()
        let начало = часы.now
        var записьСобытия = СостояниеЗаписиСобытия.неНачата
        var принятое: Квитанция?
        do {
            let путь = try ПутьХранилища.подготовить(параметры.хранилище)
            let идентификатор = параметры.событие ?? UUID().uuidString.lowercased()
            let наблюдение = НачальноеНамерение(версияСхемы: 1, намерение: параметры.намерение,
                подключённыеАдаптеры: [])
            let данные = try ПредставлениеЗапуска.байты(наблюдение)
            let спецификация = Data("fuma.начальный-запуск.1: намерение и локальная история; адаптеры ожидают подключения".utf8)
            let время = ISO8601DateFormatter()
            время.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
            время.timeZone = TimeZone(secondsFromGMT: 0)
            let сохранение = try Self.сохранитьИПереоткрытьСегмент(
                путь: путь, идентификатор: идентификатор, данные: данные, операции: операции,
                кодНеизвестнойОшибки: .внутренняя
            ) { прежнее in
                if let прежнее {
                    guard прежнее.тип == "начальный-запуск", прежнее.версияСхемы == 1,
                          прежнее.источник == "fuma", прежнее.спецификация == спецификация,
                          время.date(from: прежнее.время) != nil else {
                        throw ОтказЗапуска(код: .несовместимаяЗапись,
                            сообщение: "Этот ID принадлежит несовместимому описанию; его поля не заменяются.")
                    }
                    return прежнее
                }
                return ОписаниеНаблюдения(идентификатор: идентификатор, тип: "начальный-запуск",
                    версияСхемы: 1, источник: "fuma", время: время.string(from: Date()),
                    спецификация: спецификация)
            }
            let квитанция = сохранение.квитанция
            принятое = квитанция
            записьСобытия = .подтверждена
            let принятоеНаблюдение = try JSONDecoder().decode(
                НачальноеНамерение.self, from: сохранение.байтыПовторногоЧтения)
            let интервал = начало.duration(to: часы.now).components
            let наносекунды = UInt64(интервал.seconds) * 1_000_000_000 + UInt64(интервал.attoseconds / 1_000_000_000)
            return РезультатЦикла(квитанция: квитанция, наблюдение: принятоеНаблюдение,
                изменение: сохранение.точныйПовтор ? .точныйПовтор : .добавлено,
                принятоЗаписей: сохранение.количествоЗаписей, провереноПослеПереоткрытия: true,
                полезныйЦиклНаносекунды: параметры.профиль ? наносекунды : nil)
        } catch let ошибка as ОшибкаСегментногоСохранения {
            throw ошибка.отказ
        } catch let ошибка as ОтказЗапуска {
            throw ОтказЗапуска(код: ошибка.код, сообщение: ошибка.сообщение,
                системныйКод: ошибка.системныйКод, записьСобытия: записьСобытия,
                принятаяКвитанция: принятое)
        } catch let ошибка as ОшибкаКонтейнера {
            let код: КодОтказаЗапуска
            let системныйКод: Int32?
            switch ошибка {
            case .система(let значение):
                системныйКод = значение
                код = значение == ELOOP || значение == ENOTDIR ? .небезопасныйПуть : .системнаяОшибка
            case .повреждение: код = .повреждениеИстории; системныйКод = nil
            case .предел: код = .предел; системныйКод = nil
            case .неполныйХвост: код = .неполныйХвост; системныйКод = nil
            case .конфликтИдентификатора: код = .конфликтИдентификатора; системныйКод = nil
            case .занят: код = .хранилищеЗанято; системныйКод = nil
            case .небезопасныйПуть: код = .небезопасныйПуть; системныйКод = nil
            case .нетЗаписи, .закрыт, .толькоЧтение: код = .внутренняя; системныйКод = nil
            }
            throw ОтказЗапуска(код: код, сообщение: String(describing: ошибка),
                системныйКод: системныйКод, записьСобытия: записьСобытия,
                принятаяКвитанция: принятое)
        } catch let ошибка {
            throw ОтказЗапуска(код: .внутренняя, сообщение: String(describing: ошибка),
                записьСобытия: записьСобытия, принятаяКвитанция: принятое)
        }
    }
}

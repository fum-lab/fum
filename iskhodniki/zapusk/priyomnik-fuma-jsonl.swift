import АрхивныйСнимокЗадачи
import Foundation
import FUMStructuringOperatorMemory

/// Синхронно связывает LF-фреймер с закреплённой JSONL→FUMA-машиной.
/// Не хранит историю кадров: владелец получает каждый исход в callback.
public final class ПоследовательнаяПроекцияJSONL {
    public let источник: String
    private let фреймер: ПоследовательныеРамкиJSONL

    public init(
        источник: String,
        начальноеСмещение: Int = 0
    ) throws {
        self.источник = источник
        фреймер = try ПоследовательныеРамкиJSONL(начальноеСмещение: начальноеСмещение)
    }

    /// Передаёт исходный результат фиксированной машины без преобразования.
    /// Любой throw остаётся терминальным для экземпляра фреймера.
    @discardableResult
    public func принять(
        _ данные: Data,
        смещение: Int,
        обработать: (ИсходФасадаJSONL) throws -> Void
    ) throws -> Int {
        try фреймер.принять(данные, смещение: смещение) { [источник] рамка in
            let срез = СрезJSONL(
                данные: рамка.данные,
                привязка: ПривязкаСрезаJSONL(
                    источник: источник,
                    смещение: рамка.позиция.начало,
                    длина: рамка.данные.count,
                    ожидаемыйSHA256: рамка.позиция.sha256))
            try обработать(FUMStructuringOperatorMemory.ФасадJSONL.выполнить(срез))
        }
    }

    /// Возвращает исходный хвост EOF отдельно; он не становится JSONL-кадром.
    public func завершить() throws -> ИтогПоследовательныхРамок {
        try фреймер.завершить()
    }
}

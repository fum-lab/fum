import Foundation

enum ИзменённыеСтроки {
    static func прочитать(_ данные: Data, всегоСтрок: Int) throws -> Set<Int> {
        var добавлены: Set<Int> = []
        var старая = 0
        var новая = 0
        var осталосьСтарых = 0
        var осталосьНовых = 0
        var былаГруппа = false
        for часть in данные.split(separator: 10, omittingEmptySubsequences: false) {
            guard let строка = String(data: часть, encoding: .utf8) else { throw ОтказЧитателяЯзыка.формат }
            if строка.hasPrefix("@@ ") {
                guard осталосьСтарых == 0, осталосьНовых == 0 else { throw ОтказЧитателяЯзыка.формат }
                let части = строка.split(separator: " ")
                guard части.count >= 4, части[0] == "@@", части[3] == "@@" else {
                    throw ОтказЧитателяЯзыка.формат
                }
                let прежний = try диапазон(части[1], знак: "-")
                let следующий = try диапазон(части[2], знак: "+")
                guard следующий.0 <= всегоСтрок, следующий.1 <= всегоСтрок,
                      следующий.0 + следующий.1 <= всегоСтрок + 1 else { throw ОтказЧитателяЯзыка.формат }
                старая = прежний.0; новая = следующий.0
                осталосьСтарых = прежний.1; осталосьНовых = следующий.1; былаГруппа = true
                continue
            }
            guard былаГруппа else { continue }
            if строка.hasPrefix("\\ No newline at end of file") { continue }
            if осталосьСтарых == 0 && осталосьНовых == 0 {
                guard строка.isEmpty else { throw ОтказЧитателяЯзыка.формат }
                continue
            }
            if строка.first == "+" {
                guard осталосьНовых > 0, новая > 0 else { throw ОтказЧитателяЯзыка.формат }
                добавлены.insert(новая); новая += 1; осталосьНовых -= 1
            } else if строка.first == "-" {
                guard осталосьСтарых > 0 else { throw ОтказЧитателяЯзыка.формат }
                старая += 1; осталосьСтарых -= 1
            } else if строка.first == " " {
                guard осталосьСтарых > 0, осталосьНовых > 0 else { throw ОтказЧитателяЯзыка.формат }
                старая += 1; новая += 1; осталосьСтарых -= 1; осталосьНовых -= 1
            } else { throw ОтказЧитателяЯзыка.формат }
        }
        guard осталосьСтарых == 0, осталосьНовых == 0 else { throw ОтказЧитателяЯзыка.формат }
        return добавлены
    }

    static func строкиГит(_ данные: Data) -> [Int] {
        var соответствие = [1]
        var строкаГит = 1
        var предыдущийВозвратКаретки = false
        for байт in данные {
            if байт == 13 { соответствие.append(строкаГит) }
            if байт == 10 {
                строкаГит += 1
                if предыдущийВозвратКаретки { соответствие[соответствие.count - 1] = строкаГит }
                else { соответствие.append(строкаГит) }
            }
            предыдущийВозвратКаретки = байт == 13
        }
        return соответствие
    }

    private static func диапазон(_ текст: Substring, знак: Character) throws -> (Int, Int) {
        guard текст.first == знак else { throw ОтказЧитателяЯзыка.формат }
        let части = текст.dropFirst().split(separator: ",", omittingEmptySubsequences: false)
        guard (1...2).contains(части.count), let начало = Int(части[0]), начало >= 0,
              let число = части.count == 1 ? 1 : Int(части[1]), число >= 0,
              начало <= 4_194_304, число <= 4_194_304 else { throw ОтказЧитателяЯзыка.формат }
        return (начало, число)
    }
}

    @Test("Throw apply после возможного эффекта сообщает неизвестность без квитанции и повтора")
    func неизвестныйИсходApply() async throws {
        let временный = try ВременныйКаталогПакетаПутей()
        let план = try временный.записать(Data([0x10, 0x20]), под: "план.json")
        let адаптер = АдаптерПакетаПутейДляТестов(ошибкаПрименения: true)
        let результат = await ОбработчикПакетаПутей(адаптер: адаптер).выполнить([

import Testing
@testable import ОсноваЗапуска

@Suite("CLI пакета путей", .serialized)
struct ПроверкиПакетаПутей {
    private let корень = FileManager.default.temporaryDirectory
        .appendingPathComponent("fuma-пакет-путей", isDirectory: true)
    private let хэш = String(repeating: "a", count: 64)
    private var путьВременногоПоручения: String {
        FileManager.default.temporaryDirectory.appendingPathComponent("поручение.json").path
    }
    private var путьВременногоПлана: String {
        FileManager.default.temporaryDirectory.appendingPathComponent("план.json").path
    }

    @Test("Парсер распознаёт точные формы трёх действий")
    func формыДействий() throws {
        let построение = try РазборПакетаПутей.разобрать([
            "построить", "--корень", корень.path, "--вход", путьВременногоПоручения
        ])
        guard case .построить(let кореньПостроения, let вход) = построение else {
            Issue.record("Построение получило другой маршрут")
            return
        }
        #expect(кореньПостроения == корень)
        #expect(вход.path == путьВременногоПоручения)

        let сверка = try РазборПакетаПутей.разобрать([
            "сверить", "--корень", корень.path, "--план", путьВременногоПлана, "--sha256", хэш
        ])
        guard case .сверить(let кореньСверки, let планСверки, let shaСверки) = сверка else {
            Issue.record("Сверка получила другой маршрут")
            return
        }
        #expect(кореньСверки == корень)
        #expect(планСверки.path == путьВременногоПлана)
        #expect(shaСверки == хэш)

        let применение = try РазборПакетаПутей.разобрать([
            "применить", "--корень", корень.path, "--план", путьВременногоПлана, "--sha256", хэш
        ])
        guard case .применить(let кореньПрименения, let планПрименения, let shaПрименения) = применение else {
            Issue.record("Применение получило другой маршрут")
            return
        }
        #expect(кореньПрименения == корень)
        #expect(планПрименения.path == путьВременногоПлана)
        #expect(shaПрименения == хэш)
    }

    @Test("Отсутствующие, повторные и неизвестные аргументы отклоняются до адаптера")
    func неверныеАргументыДоАдаптера() async {
        let неверные: [[String]] = [
            [],
            ["построить", "--корень", корень.path],
            ["построить", "--корень", корень.path, "--вход", путьВременногоПоручения, "--вход", путьВременногоПлана],
            ["построить", "--корень", корень.path, "--вход", путьВременногоПоручения, "--неизвестно", "x"],
            ["сверить", "--корень", корень.path, "--план", путьВременногоПлана],
            ["применить", "--корень", "относительный", "--план", путьВременногоПлана, "--sha256", хэш],
            ["сверить", "--корень", корень.path, "--план", путьВременногоПлана, "--sha256", String(repeating: "A", count: 64)],
            ["сверить", "--корень", корень.path, "--план", путьВременногоПлана, "--sha256", String(repeating: "a", count: 63)]
        ]
        for аргументы in неверные {
            let адаптер = АдаптерПакетаПутейДляТестов()
            let результат = await ОбработчикПакетаПутей(адаптер: адаптер).выполнить(аргументы)
            #expect(результат.код == 2)
            #expect(результат.вывод.isEmpty)
            #expect(await адаптер.вызовы.isEmpty)
        }
    }

    @Test("Построение и сверка передают точные Data и SHA; сверка не создаёт тело")
    func точныеВходыПостроенияИСверки() async throws {
        let временный = try ВременныйКаталогПакетаПутей()
        let поручение = Data([0x7b, 0x00, 0xff, 0x0a, 0x7d])
        let план = Data([0x00, 0xc3, 0x28, 0x7d])
        let ответПостроения = Data([0xff, 0x00, 0x7b])
        try поручение.write(to: временный.url.appendingPathComponent("поручение.json"))
        try план.write(to: временный.url.appendingPathComponent("план.json"))

        let адаптерПостроения = АдаптерПакетаПутейДляТестов(ответПостроения: ответПостроения)
        let результатПостроения = await ОбработчикПакетаПутей(адаптер: адаптерПостроения).выполнить([
            "построить", "--корень", корень.path, "--вход", временный.url.appendingPathComponent("поручение.json").path
        ])
        #expect(результатПостроения.код == 0)
        #expect(результатПостроения.вывод == ответПостроения)
        let вызовПостроения = try #require(await адаптерПостроения.вызовы.first)
        #expect(вызовПостроения == .построить(корень, поручение))

        let адаптерСверки = АдаптерПакетаПутейДляТестов()
        let результатСверки = await ОбработчикПакетаПутей(адаптер: адаптерСверки).выполнить([
            "сверить", "--корень", корень.path, "--план", временный.url.appendingPathComponent("план.json").path,
            "--sha256", хэш
        ])
        #expect(результатСверки.код == 0)
        #expect(результатСверки.вывод.isEmpty)
        #expect(await адаптерСверки.вызовы == [.сверить(корень, план, хэш)])
    }

    @Test("Четыре допустимых исхода сохраняют квитанцию без изменения байтов",
          arguments: ["завершено", "откат-проверен", "частичный", "неизвестно"])
    func исходыКвитанции(_ исход: String) async throws {
        let временный = try ВременныйКаталогПакетаПутей()
        let план = try временный.записать(Data([0x00, 0xff]), под: "план.json")
        let квитанция = try допустимаяКвитанция(исход: исход)
        let адаптер = АдаптерПакетаПутейДляТестов(ответПрименения: квитанция)
        let результат = await ОбработчикПакетаПутей(адаптер: адаптер).выполнить([
            "применить", "--корень", корень.path, "--план", план.path, "--sha256", хэш
        ])

        #expect(результат.код == (исход == "завершено" ? 0 : 2))
        #expect(результат.вывод == квитанция)
        #expect(await адаптер.вызовы == [.применить(корень, Data([0x00, 0xff]), хэш)])
    }


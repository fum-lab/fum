            Data(#"{"схема":"fum.квитанция-пакета-девяти-путей.1","план_sha256":"\#(String(repeating: "b", count: 64))","исход":"завершено","подтверждённый_префикс":14,"наблюдённый_префикс":14}"#.utf8),
            Data(#"{"схема":"fum.квитанция-пакета-девяти-путей.1","план_sha256":"\#(хэш)","исход":"успех","подтверждённый_префикс":14,"наблюдённый_префикс":14}"#.utf8)

            .init(исход: "откат-проверен", подтверждённыйПрефикс: -1, наблюдённыйПрефикс: 0, причина: "причина"),
            .init(исход: "откат-проверен", подтверждённыйПрефикс: 15, наблюдённыйПрефикс: 0, причина: "причина"),

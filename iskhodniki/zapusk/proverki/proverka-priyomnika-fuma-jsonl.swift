import Testing

struct ПроверкаПриёмникаJSONL {
    private enum ОшибкаCallback: Error, Equatable {
        case остановить
    }

    private func хэш(_ данные: Data) -> String {
        SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
    }

    private func рамка(_ текст: String) -> Data {
        Data((текст + "\n").utf8)
    }

    @Test("message и function_call_output сохраняют байты, смещения и хвост EOF")
    func поддержанныеФормыСохраняютИсходныеРамки() throws {
        let источник = "synthetic-jsonl"
        let начало = 4_096
        let сообщение = Data(
            #"{"type":"response_item","payload":{"type":"message","role":"assistant","content":[{"type":"output_text","text":"Привет, ёж!"}]}}"#.utf8
        ) + Data([0x0D, 0x0A])
        let вывод = Data(
            #"{"type":"response_item","payload":{"type":"function_call_output","output":"<result>готово</result>"}}"#.utf8
        ) + Data([0x0A])
        let хвост = Data([0x7B, 0x22, 0x74, 0x79])
        let вход = сообщение + вывод + хвост
        let маркер = Data("ё".utf8)
        guard let позицияМаркера = вход.range(of: маркер) else {
            Issue.record("В фикстуре нет многобайтного UTF-8-маркера")
            return
        }
        let разрез = позицияМаркера.lowerBound + 1
        let разборщик = try ПоследовательнаяПроекцияJSONL(
            источник: источник, начальноеСмещение: начало)
        var исходы: [ИсходФасадаJSONL] = []
        var следующее = начало
        for часть in [Data(вход[..<разрез]), Data(вход[разрез...])] {
            следующее = try разборщик.принять(часть, смещение: следующее) {
                исходы.append($0)
            }
        }
        let итог = try разборщик.завершить()

        #expect(следующее == начало + вход.count)
        #expect(итог.следующееСмещение == следующее)
        #expect(итог.сыройХвост == хвост)
        #expect(исходы.count == 2)

        guard исходы.count == 2,
              case .проецировано(let проекцияСообщения) = исходы[0],
              case .проецировано(let проекцияВывода) = исходы[1] else {
            Issue.record("Ожидались две проекции фиксированного оператора")
            return
        }
        #expect(проекцияСообщения.исходныйСрез.данные == сообщение)
        #expect(проекцияСообщения.исходныйСрез.привязка == ПривязкаСрезаJSONL(
            источник: источник, смещение: начало, длина: сообщение.count,
            ожидаемыйSHA256: хэш(сообщение)))
        #expect(проекцияСообщения.payloadТип == "message")
        #expect(проекцияСообщения.текстовыеЧасти == [
            ЧастьТекстаJSONL(тип: "output_text", текст: "Привет, ёж!")
        ])
        #expect(проекцияВывода.исходныйСрез.данные == вывод)
        #expect(проекцияВывода.исходныйСрез.привязка == ПривязкаСрезаJSONL(
            источник: источник, смещение: начало + сообщение.count, длина: вывод.count,
            ожидаемыйSHA256: хэш(вывод)))
        #expect(проекцияВывода.payloadТип == "function_call_output")
        #expect(проекцияВывода.текстовыеЧасти == [
            ЧастьТекстаJSONL(тип: "function_call_output", текст: "<result>готово</result>")
        ])
    }

    @Test("неизвестные, ошибочные UTF-8 и сырой хвост передаются без потери байтов")
    func непроецируемыеРамкиИОстатокСохраняются() throws {
        let источник = "opaque-jsonl"
        let начало = 31
        let неизвестная = рамка(#"{"type":"other","payload":{}}"#)
        let плохойUTF8 = Data([0xFF, 0x0A])
        let хвост = Data([0x7B, 0x22])
        let вход = неизвестная + плохойUTF8 + хвост
        let разборщик = try ПоследовательнаяПроекцияJSONL(
            источник: источник, начальноеСмещение: начало)
        var исходы: [ИсходФасадаJSONL] = []
        _ = try разборщик.принять(вход, смещение: начало) { исходы.append($0) }
        let итог = try разборщик.завершить()

        #expect(исходы.count == 2)
        #expect(итог.сыройХвост == хвост)
        guard исходы.count == 2 else { return }
        for (номер, исход) in исходы.enumerated() {
            let исходныеДанные = номер == 0 ? неизвестная : плохойUTF8
            let смещение = начало + (номер == 0 ? 0 : неизвестная.count)
            switch исход {
            case .неподдержано(let срез, _), .отклонено(let срез, _, _):
                #expect(срез.данные == исходныеДанные)
                #expect(срез.привязка == ПривязкаСрезаJSONL(
                    источник: источник, смещение: смещение,
                    длина: исходныеДанные.count, ожидаемыйSHA256: хэш(исходныеДанные)))
            case .проецировано:
                Issue.record("Неизвестная или повреждённая рамка не должна проецироваться")
            }
        }

        let длинныйИсточник = String(repeating: "x", count: 257)
        let источникПредела = try ПоследовательнаяПроекцияJSONL(источник: длинныйИсточник)
        var отказано: ИсходФасадаJSONL?
        _ = try источникПредела.принять(неизвестная, смещение: 0) { отказано = $0 }
        guard case .отклонено(let срез, let код, _) = отказано else {
            Issue.record("Идентификатор источника длиннее 256 UTF-8 байт должен быть отклонён")
            return
        }
        #expect(код == "источник")
        #expect(срез.данные == неизвестная)
        #expect(срез.привязка.источник == длинныйИсточник)
    }

    @Test("ошибка callback после префикса терминальна и не выдаёт следующую рамку")
    func ошибкаCallbackОстанавливаетПрефикс() throws {
        let вход = рамка(#"{"type":"other"}"#)
            + рамка(#"{"type":"other"}"#)
            + рамка(#"{"type":"other"}"#)
        let разборщик = try ПоследовательнаяПроекцияJSONL(источник: "callback-failure")
        var вызовы = 0
        do {
            _ = try разборщик.принять(вход, смещение: 0) { _ in
                вызовы += 1
                if вызовы == 2 { throw ОшибкаCallback.остановить }
            }
            Issue.record("Ожидалась ошибка callback")
        } catch let ошибка as ОшибкаCallback {
            #expect(ошибка == .остановить)
        }
        #expect(вызовы == 2)
        do {
            _ = try разборщик.принять(Data([0x0A]), смещение: вход.count) { _ in
                Issue.record("Терминальный поток не должен вызывать callback")
            }
            Issue.record("После callback-ошибки ожидался терминальный отказ")
        } catch let ошибка as ОшибкаПоследовательныхРамок {
            #expect(ошибка == .отказ)
        }
        do {
            _ = try разборщик.завершить()
            Issue.record("После callback-ошибки завершение не должно пройти")
        } catch let ошибка as ОшибкаПоследовательныхРамок {
            #expect(ошибка == .отказ)
        }
    }

    @Test("перевход с поглощённой вложенной ошибкой всё равно терминален")
    func перевходНеПродолжаетПоток() throws {
        let вход = рамка(#"{"type":"other"}"#) + рамка(#"{"type":"other"}"#)
        let разборщик = try ПоследовательнаяПроекцияJSONL(источник: "reentry")
        var вызовы = 0
        var вложеннаяОшибка: ОшибкаПоследовательныхРамок?
        do {
            _ = try разборщик.принять(вход, смещение: 0) { _ in
                вызовы += 1
                do {
                    _ = try разборщик.принять(Data([0x0A]), смещение: 0) { _ in
                        Issue.record("Вложенный callback не должен запускаться")
                    }
                } catch let ошибка as ОшибкаПоследовательныхРамок {
                    вложеннаяОшибка = ошибка
                }
            }
            Issue.record("Ожидался отказ внешнего вызова после перевхода")
        } catch let ошибка as ОшибкаПоследовательныхРамок {
            #expect(ошибка == .отказ)
        }
        #expect(вложеннаяОшибка == .повторныйВход)
        #expect(вызовы == 1)
        do {
            _ = try разборщик.завершить()
            Issue.record("Перевошедший поток не должен завершиться")
        } catch let ошибка as ОшибкаПоследовательныхРамок {
            #expect(ошибка == .отказ)
        }
    }

    @Test("ошибка смещения и предел порции не допускают продолжение")
    func смещениеИПределТерминальны() throws {
        let смещение = try ПоследовательнаяПроекцияJSONL(
            источник: "offset", начальноеСмещение: 100)
        do {
            _ = try смещение.принять(Data([0x0A]), смещение: 101) { _ in }
            Issue.record("Ожидался разрыв смещения")
        } catch let ошибка as ОшибкаПоследовательныхРамок {
            #expect(ошибка == .разрывСмещения(ожидалось: 100, получено: 101))
        }
        do {
            _ = try смещение.принять(Data([0x0A]), смещение: 100) { _ in }
            Issue.record("После разрыва ожидался терминальный отказ")
        } catch let ошибка as ОшибкаПоследовательныхРамок {
            #expect(ошибка == .отказ)
        }

        let ограниченныйПоток = try ПоследовательнаяПроекцияJSONL(источник: "limit")
        do {
            let превышениеПорции = Data(repeating: 0x20, count: 1_048_577)
            _ = try ограниченныйПоток.принять(превышениеПорции, смещение: 0) { _ in }
            Issue.record("Ожидался отказ предела порции")
        } catch let ошибка as ОшибкаАрхива {
            #expect(ошибка == .предел)
        }
        do {
            _ = try ограниченныйПоток.завершить()
            Issue.record("После отказа предела завершение не должно пройти")
        } catch let ошибка as ОшибкаПоследовательныхРамок {
            #expect(ошибка == .отказ)
        }
    }
}

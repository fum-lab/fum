private struct СерияПрофиляСвязи: Encodable, Sendable {
    let номер: Int
    let вызовов: Int
    let наносекунды: UInt64
}

private struct ЗаписьПрофиляСвязи: Encodable, Sendable {
    let схема: String
    let условия: String
    let хэшИсточника: String
    let принятыйКоммит: String
    let принятоеДерево: String
    let серии: [СерияПрофиляСвязи]
    let решение: String
}

@Suite("Профиль версионной связи приёмки", .serialized)
struct ПрофильВерсионнойСвязиПриёмки {
    @Test("три серии по десять pure Data вызовов")
    func измерить() throws {
        let данные = try ФикстураСвязиПриёмки.актуальныеДанные()
        var серии: [СерияПрофиляСвязи] = []
        for номер in 1...3 {
            let начало = DispatchTime.now().uptimeNanoseconds
            var последняя: ПринятаяВерсияКомпозиции?
            for _ in 0..<10 {
                последняя = try ПроверкаСвязиПриёмкиКомпозиции.принять(
                    данные, ожидается: ФикстураСвязиПриёмки.ожидаемая)
            }
            let конец = DispatchTime.now().uptimeNanoseconds
            #expect(последняя?.коммит == ФикстураСвязиПриёмки.принятыйКоммит)
            серии.append(СерияПрофиляСвязи(
                номер: номер, вызовов: 10, наносекунды: конец - начало))
        }
        let хэш = SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
        let запись = ЗаписьПрофиляСвязи(
            схема: "fum.профиль-версионной-связи-приёмки.2",
            условия: "3 последовательные серии по 10 вызовов; один неизменный Data; SwiftPM debug; внешние монотонные часы; без сравниваемого варианта",
            хэшИсточника: хэш,
            принятыйКоммит: ФикстураСвязиПриёмки.принятыйКоммит,
            принятоеДерево: ФикстураСвязиПриёмки.принятоеДерево,
            серии: серии,
            решение: "Сравнимого варианта нет; профиль не доказывает ускорение и не выбирает оптимизацию.")
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys]
        let вывод = try кодировщик.encode(запись)
        print("ФУМА_ПРОФИЛЬ_ВЕРСИОННОЙ_СВЯЗИ=" + String(decoding: вывод, as: UTF8.self))
    }
}

private enum ОшибкаФикстуры: Error {
    case невернаяФорма
}

private func изменить(
    _ данные: Data,
    _ преобразовать: (inout [String: Any]) throws -> Void
) throws -> Data {
    guard var корень = try JSONSerialization.jsonObject(with: данные) as? [String: Any] else {
        throw ОшибкаФикстуры.невернаяФорма
    }
    try преобразовать(&корень)
    return try JSONSerialization.data(withJSONObject: корень, options: [.sortedKeys])
}

private func изменитьСловарь(
    _ корень: inout [String: Any],
    путь: [String],
    _ преобразовать: (inout [String: Any]) throws -> Void
) throws {
    guard let первый = путь.first,
          var значение = корень[первый] as? [String: Any] else {
        throw ОшибкаФикстуры.невернаяФорма
    }
    if путь.count == 1 {
        try преобразовать(&значение)
    } else {
        try изменитьСловарь(&значение, путь: Array(путь.dropFirst()), преобразовать)
    }
    корень[первый] = значение
}

@Suite("Адресная проверка версионной связи приёмки", .serialized)
struct ПроверкиВерсионнойСвязиПриёмки {
    private func ожидатьОтказ(_ данные: Data) {
        #expect(throws: ОшибкаСвязиПриёмки.неверныйДокумент) {
            try ПроверкаСвязиПриёмкиКомпозиции.принять(
                данные, ожидается: ФикстураСвязиПриёмки.ожидаемая)
        }
    }

    @Test("актуальная версия 2 возвращает только закреплённую принятую версию")
    func актуальныйДокумент() throws {
        let результат = try ПроверкаСвязиПриёмкиКомпозиции.принять(
            ФикстураСвязиПриёмки.актуальныеДанные(),
            ожидается: ФикстураСвязиПриёмки.ожидаемая)
        #expect(результат.коммит == ФикстураСвязиПриёмки.принятыйКоммит)
        #expect(результат.дерево == ФикстураСвязиПриёмки.принятоеДерево)
        #expect(результат.родитель == ФикстураСвязиПриёмки.отклонённыйКоммит)
        #expect(результат.заменяет == ФикстураСвязиПриёмки.отклонённыйКоммит)
        #expect(результат.уровень == ФикстураСвязиПриёмки.уровень)
    }

    @Test("ложное принято у legacy ce4 отклоняется при правильном вложенном 3557")
    func ложнаяМеткаПрежнейВерсии() throws {
        let данные = try изменить(ФикстураСвязиПриёмки.актуальныеДанные()) { корень in
            try изменитьСловарь(&корень, путь: [
                "следующее_назначение_чистой_композиции", "добавочная_коррекция",
            ]) { $0["принято"] = true }
        }
        ожидатьОтказ(данные)
    }

    @Test("старый документ без новой связи отклоняется")
    func старыйДокумент() throws {
        let данные = try изменить(ФикстураСвязиПриёмки.актуальныеДанные()) { корень in
            корень["версия"] = 1
            корень.removeValue(forKey: "связь_приёмки_композиции")
            try изменитьСловарь(&корень, путь: [
                "следующее_назначение_чистой_композиции", "добавочная_коррекция",
            ]) { $0["принято"] = true }
        }
        ожидатьОтказ(данные)

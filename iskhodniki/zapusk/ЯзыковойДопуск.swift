import Foundation

public struct НарушениеЯзыковогоДопуска: Codable, Equatable, Sendable {
    public let имя: String
    public let вид: String
    public let путь: String
    public let строка: Int
    public let столбец: Int
    public let причина: String
    public let начальнаяСтрока: Int

    public init(имя: String, вид: String, путь: String, строка: Int, столбец: Int,
                причина: String = "нерусский-алфавит", начальнаяСтрока: Int? = nil) {
        self.имя = имя
        self.вид = вид
        self.путь = путь
        self.строка = строка
        self.столбец = столбец
        self.причина = причина
        self.начальнаяСтрока = начальнаяСтрока ?? строка
    }
}

/// Первый ограниченный профиль: собственные объявления изменяемого Swift-исходника.
public enum ПроверкаЯзыкаСвифта {
    public static func проверить(текст: String, путь: String) throws -> [НарушениеЯзыковогоДопуска] {
        try проверить(текст: текст, путь: путь, исключения: [])
    }

    static func проверить(текст: String, путь: String,
        исключения: [ИсключениеЯзыковогоДопуска]) throws -> [НарушениеЯзыковогоДопуска] {
        var лексер = ЛексерЯзыковогоДопуска(текст)
        let лексемы = try лексер.прочитать()
        let объявления = try СканерОбъявлений.прочитать(лексемы)
        let конечныеИсключения = исключения + (try КонтекстВнешнихИмён.получить(текст: текст, путь: путь))
        var нарушения: [НарушениеЯзыковогоДопуска] = []
        for объявление in объявления {
            let имя = объявление.имя
            if имя.текст == "_" { continue }
            if конечныеИсключения.contains(where: { $0.разрешает(путь: путь, вид: объявление.вид,
                имя: имя.текст, строка: имя.строка, столбец: имя.столбец) }) {
                continue
            }
            if let причина = ОрфографияОбъявлений.причина(имя.текст) {
                нарушения.append(.init(имя: имя.текст, вид: объявление.вид, путь: путь,
                    строка: имя.строка, столбец: имя.столбец, причина: причина,
                    начальнаяСтрока: объявление.начальнаяСтрока))
            }
        }
        return нарушения
    }
}

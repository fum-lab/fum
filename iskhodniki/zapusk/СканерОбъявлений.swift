import Foundation

struct ОбъявлениеЯзыковогоДопуска {
    let имя: ЛексемаЯзыковогоДопуска
    let вид: String
    let начальнаяСтрока: Int
}

/// Конечный лексический профиль, без разрешения типов или доказательства соответствия протоколу.
enum СканерОбъявлений {
    static func прочитать(_ слова: [ЛексемаЯзыковогоДопуска], профильРолей: Bool = false) throws -> [ОбъявлениеЯзыковогоДопуска] {
        let виды: Set<String> = ["func", "class", "struct", "enum", "protocol", "actor",
            "typealias", "associatedtype", "let", "var"]
        var результат: [ОбъявлениеЯзыковогоДопуска] = []
        var области: [Bool] = []
        var скобки: [Int] = []
        var ожидаетПеречисление = false
        var разрешённыеВхождения: Set<Int> = []
        for номер in слова.indices {
            let слово = слова[номер]
            let текст = слово.текст
            if текст == "(", возможныйКортеж(слова, номер: номер) {
                try меткиКортежа(слова, начало: номер, результат: &результат)
            }
            if текст == "{" { области.append(ожидаетПеречисление); скобки.append(номер); ожидаетПеречисление = false }
            if текст == "}" { if !области.isEmpty { области.removeLast(); скобки.removeLast() } }
            guard !слово.экранирована else { continue }
            if номер > 0 && [".", "import"].contains(слова[номер - 1].текст) { continue }
            if ["macro", "operator", "precedencegroup"].contains(текст) {
                throw отказ(слово, "macro/operator/precedencegroup")
            }
            if текст == "in" && !разрешённыеВхождения.contains(номер) {
                if номер + 1 < слова.count, слова[номер + 1].текст == ":" { continue }
                guard let начало = скобки.last else { throw отказ(слово, "in без начала замыкания") }
                try замыкание(слова, начало: начало, конец: номер, результат: &результат)
            }
            if ["set", "willSet", "didSet"].contains(текст), номер + 1 < слова.count,
               слова[номер + 1].текст == "(" {
                guard номер + 3 < слова.count, слова[номер + 2].имя, слова[номер + 3].текст == ")" else {
                    throw отказ(слово, "сложная подпись setter/observer")
                }
                результат.append(.init(имя: слова[номер + 2], вид: "параметр-доступа", начальнаяСтрока: слово.строка))
            }
            if текст == "for" {
                if профильРолей, номер + 1 < слова.count, слова[номер + 1].текст == ":" {
                    guard меткаПервогоАргумента(слова, номер: номер) else {
                        throw отказ(слово, "for: вне простого именованного вызова")
                    }
                    continue
                }
                guard let конец = слова.indices.dropFirst(номер + 1).first(where: { слова[$0].текст == "in" }) else {
                    throw отказ(слово, "for без in")
                }
                var привязка = Array(слова[(номер + 1)..<конец])
                if привязка.first?.текст == "try", привязка.first?.экранирована == false { привязка.removeFirst() }
                if привязка.first?.текст == "await", привязка.first?.экранирована == false { привязка.removeFirst() }
                guard !привязка.isEmpty, привязка.allSatisfy({ $0.имя || ["(", ")", ","].contains($0.текст) }),
                      !привязка.contains(where: { ["case", "let", "var", "try", "await"].contains($0.текст) }) else {
                    throw отказ(слово, "составной for-pattern")
                }
                for имя in привязка where имя.имя {
                    результат.append(.init(имя: имя, вид: "for", начальнаяСтрока: слово.строка))
                }
                разрешённыеВхождения.insert(конец)
            }
            if текст == "case", области.last == true {
                var курсор = номер + 1
                while курсор < слова.count {
                    guard слова[курсор].имя else { throw отказ(слово, "enum case-pattern") }
                    результат.append(.init(имя: слова[курсор], вид: "case", начальнаяСтрока: слово.строка))
                    курсор += 1
                    if курсор < слова.count, слова[курсор].текст == "=" {
                        if !профильРолей { throw отказ(слова[курсор], "raw-value enum case") }
                        курсор += 1
                        // Литералы уже защищены лексером. Именованное выражение не считается raw literal.
                        while курсор < слова.count, ![",", "case", "}"].contains(слова[курсор].текст) {
                            guard !слова[курсор].имя else { throw отказ(слова[курсор], "сложное raw value в инвентаре ролей") }
                            курсор += 1
                        }
                        if курсор < слова.count, слова[курсор].текст == "," { курсор += 1; continue }
                        break
                    }
                    if курсор < слова.count, слова[курсор].текст == "(" {
                        курсор = try параметры(слова, начало: курсор, строка: слово.строка,
                                              результат: &результат, безымянныеТипы: true)
                    }
                    if курсор < слова.count, слова[курсор].текст == "," { курсор += 1; continue }
                    break
                }
            }
            if ["init", "subscript"].contains(текст) {
                var курсор = номер + 1
                if курсор < слова.count, ["?", "!"].contains(слова[курсор].текст) { курсор += 1 }
                if курсор < слова.count, слова[курсор].текст == "<" {
                    курсор = try обобщение(слова, начало: курсор, строка: слово.строка, результат: &результат)
                }
                if курсор < слова.count, слова[курсор].текст == "(" {
                    _ = try параметры(слова, начало: курсор, строка: слово.строка, результат: &результат)
                }
            }
            guard виды.contains(текст) else { continue }
            guard номер + 1 < слова.count else { throw отказ(слово, "объявление без имени") }
            let имя = слова[номер + 1]
            if текст == "class", ["func", "var", "let"].contains(имя.текст) { continue }
            if профильРолей, ["let", "var"].contains(текст), имя.текст == "(" {
                let после = try кортежПривязок(слова, начало: номер + 1, результат: &результат)
                try проверитьОднуПривязку(слова, начало: после, профильРолей: true, результат: &результат)
                continue
            }
            guard имя.имя else { throw отказ(имя, "tuple/operator/неизвестное имя") }
            результат.append(.init(имя: имя, вид: текст, начальнаяСтрока: слово.строка))
            if текст == "enum" { ожидаетПеречисление = true }
            var курсор = номер + 2
            if курсор < слова.count, слова[курсор].текст == "<" {
                курсор = try обобщение(слова, начало: курсор, строка: слово.строка, результат: &результат)
            }
            if текст == "func", курсор < слова.count, слова[курсор].текст == "(" {
                _ = try параметры(слова, начало: курсор, строка: слово.строка, результат: &результат)
            }
            if ["let", "var"].contains(текст) {
                try проверитьОднуПривязку(слова, начало: номер + 2, профильРолей: профильРолей, результат: &результат)
            }
        }
        return результат
    }

    private static func возможныйКортеж(_ слова: [ЛексемаЯзыковогоДопуска], номер: Int) -> Bool {
        if номер == 0 { return true }
        let предыдущее = слова[номер - 1]
        if ["return", "throw", "yield", "as", "is", "some", "any", "await", "try"].contains(предыдущее.текст),
           !предыдущее.экранирована { return true }
        if предыдущее.текст == ">" {
            return номер >= 2 && слова[номер - 2].текст == "-"
        }
        return !предыдущее.имя && ![")", "]", "."].contains(предыдущее.текст)
    }

    private static func меткиКортежа(_ слова: [ЛексемаЯзыковогоДопуска], начало: Int,
        результат: inout [ОбъявлениеЯзыковогоДопуска]) throws {
        var глубина = 0
        var началоЭлемента = true
        for номер in (начало + 1)..<слова.count {
            let слово = слова[номер]
            if глубина == 0 {
                if слово.текст == ")" { return }
                if слово.текст == "," { началоЭлемента = true; continue }
                if началоЭлемента, слово.имя, номер + 1 < слова.count, слова[номер + 1].текст == ":" {
                    результат.append(.init(имя: слово, вид: "элемент-кортежа", начальнаяСтрока: слова[начало].строка))
                }
                началоЭлемента = false
            }
            if ["(", "[", "{"].contains(слово.текст) { глубина += 1 }
            if [")", "]", "}"].contains(слово.текст) { глубина -= 1 }
        }
        throw отказ(слова[начало], "незакрытый кортеж")
    }

    private static func параметры(_ слова: [ЛексемаЯзыковогоДопуска], начало: Int,
        строка: Int, результат: inout [ОбъявлениеЯзыковогоДопуска],
        безымянныеТипы: Bool = false) throws -> Int {
        var уровень = 0
        var сегмент: [ЛексемаЯзыковогоДопуска] = []
        for номер in (начало + 1)..<слова.count {
            let слово = слова[номер]
            if уровень == 0, [",", ")"].contains(слово.текст) {
                if let двоеточие = сегмент.firstIndex(where: { $0.текст == ":" }) {
                    let имена = сегмент.prefix(двоеточие)
                    guard (1...2).contains(имена.count), имена.allSatisfy(\.имя) else {
                        throw отказ(слово, "сложные параметры")
                    }
                    for имя in имена {
                        результат.append(.init(имя: имя, вид: "параметр", начальнаяСтрока: строка))
                    }
                } else if !сегмент.isEmpty && !безымянныеТипы {
                    throw отказ(слово, "параметр без типа")
                }
                сегмент = []
                if слово.текст == ")" { return номер + 1 }
                continue
            }
            if ["(", "[", "{"].contains(слово.текст) { уровень += 1 }
            if [")", "]", "}"].contains(слово.текст) { уровень -= 1 }
            сегмент.append(слово)
        }
        throw ОтказЯзыковогоДопуска.неподдержанныйСинтаксис("Незакрытые параметры")
    }

    private static func проверитьОднуПривязку(_ слова: [ЛексемаЯзыковогоДопуска], начало: Int,
        профильРолей: Bool, результат: inout [ОбъявлениеЯзыковогоДопуска]) throws {
        var уровень = 0
        for номер in начало..<слова.count {
            let слово = слова[номер]
            if уровень == 0 {
                if [";", "}"].contains(слово.текст) { return }
                if !слово.экранирована, номер == 0 || слова[номер - 1].текст != ".",
                   ["let", "var", "func", "return", "case"].contains(слово.текст) { return }
                if слово.текст == ",", номер + 1 < слова.count, слова[номер + 1].текст == "(" {
                    if !профильРолей { throw отказ(слово, "второй tuple-binding") }
                    let после = try послеКруглыхСкобок(слова, начало: номер + 1)
                    if после < слова.count, [":", "="].contains(слова[после].текст),
                       !(слова[после].текст == "=" && после + 1 < слова.count && слова[после + 1].текст == "=") {
                        _ = try кортежПривязок(слова, начало: номер + 1, результат: &результат)
                    }
                }
                if профильРолей, слово.текст == ",", номер + 2 < слова.count,
                   слова[номер + 1].имя, [",", "=", ":"].contains(слова[номер + 2].текст),
                   !(номер + 3 < слова.count && слова[номер + 2].текст == "=" && слова[номер + 3].текст == "=") {
                    результат.append(.init(имя: слова[номер + 1], вид: "дополнительная-привязка", начальнаяСтрока: слово.строка))
                    continue
                }
                if слово.текст == ",", номер + 2 < слова.count,
                   слова[номер + 1].имя, ["=", ":"].contains(слова[номер + 2].текст),
                   !(номер + 3 < слова.count && слова[номер + 2].текст == "=" && слова[номер + 3].текст == "=") {
                    throw отказ(слово, "несколько let/var bindings")
                }
            }
            if ["(", "[", "{"].contains(слово.текст) { уровень += 1 }
            if [")", "]", "}"].contains(слово.текст) {
                if уровень == 0 { return }
                уровень -= 1
            }
        }
    }

    private static func меткаПервогоАргумента(_ слова: [ЛексемаЯзыковогоДопуска], номер: Int) -> Bool {
        guard номер >= 2, слова[номер - 1].текст == "(" else { return false }
        let служебные: Set<String> = ["return", "throw", "try", "await", "if", "else", "guard", "while", "repeat",
            "for", "in", "switch", "case", "default", "where", "do", "catch", "defer", "break", "continue",
            "let", "var", "func", "init", "subscript", "struct", "class", "enum", "protocol", "actor",
            "typealias", "associatedtype", "macro", "operator", "precedencegroup", "as", "is", "true", "false", "nil"]
        func имяВызова(_ позиция: Int) -> Bool {
            слова[позиция].имя && (слова[позиция].экранирована || !служебные.contains(слова[позиция].текст))
        }
        var начало = номер - 2
        guard имяВызова(начало) else { return false }
        while начало >= 2, слова[начало - 1].текст == "." {
            guard имяВызова(начало - 2) else { return false }
            начало -= 2
        }
        return начало == 0 || слова[начало - 1].строка < слова[начало].строка
            || ![".", ")", "]", ">", "?", "!"].contains(слова[начало - 1].текст)
    }

    private static func послеКруглыхСкобок(_ слова: [ЛексемаЯзыковогоДопуска], начало: Int) throws -> Int {
        var глубина = 0
        for номер in начало..<слова.count {
            if слова[номер].текст == "(" { глубина += 1 }
            if слова[номер].текст == ")" {
                глубина -= 1
                if глубина == 0 { return номер + 1 }
            }
        }
        throw отказ(слова[начало], "незакрытое выражение после запятой")
    }

    private static func кортежПривязок(_ слова: [ЛексемаЯзыковогоДопуска], начало: Int,
        результат: inout [ОбъявлениеЯзыковогоДопуска]) throws -> Int {
        var глубина = 0
        var ожидаетИмя = true
        for номер in начало..<слова.count {
            let слово = слова[номер]
            if слово.текст == "(" {
                guard ожидаетИмя else { throw отказ(слово, "сложный tuple-pattern") }
                глубина += 1; continue
            }
            if слово.текст == ")" {
                guard !ожидаетИмя, глубина > 0 else { throw отказ(слово, "пустой tuple-pattern") }
                глубина -= 1
                if глубина == 0 { return номер + 1 }
                continue
            }
            if слово.текст == "," {
                guard !ожидаетИмя else { throw отказ(слово, "пустое tuple-binding") }
                ожидаетИмя = true; continue
            }
            guard ожидаетИмя, слово.имя, слово.экранирована || !["let", "var", "case"].contains(слово.текст) else {
                throw отказ(слово, "неподдержанный tuple-pattern")
            }
            результат.append(.init(имя: слово, вид: "привязка-кортежа", начальнаяСтрока: слова[начало].строка))
            ожидаетИмя = false
        }
        throw отказ(слова[начало], "незакрытый tuple-pattern")
    }

    private static func обобщение(_ слова: [ЛексемаЯзыковогоДопуска], начало: Int,
        строка: Int, результат: inout [ОбъявлениеЯзыковогоДопуска]) throws -> Int {
        var глубина = 1
        var ожидаетИмя = true
        for номер in (начало + 1)..<слова.count {
            let слово = слова[номер]
            if ожидаетИмя {
                guard слово.имя, слово.текст != "each" else { throw отказ(слово, "generic parameter-pack") }
                результат.append(.init(имя: слово, вид: "generic", начальнаяСтрока: строка))
                ожидаетИмя = false
            }
            if слово.текст == "<" { глубина += 1 }
            if слово.текст == ">" {
                глубина -= 1
                if глубина == 0 { return номер + 1 }
            }
            if слово.текст == "," && глубина == 1 { ожидаетИмя = true }
        }
        throw отказ(слова[начало], "незакрытое обобщение")
    }

    private static func замыкание(_ слова: [ЛексемаЯзыковогоДопуска], начало: Int, конец: Int,
        результат: inout [ОбъявлениеЯзыковогоДопуска]) throws {
        var подпись = Array(слова[(начало + 1)..<конец])
        guard подпись.first?.текст != "[" else { throw отказ(слова[конец], "capture-list замыкания") }
        var глубина = 0
        var стрелка: Int?
        for номер in подпись.indices {
            if ["(", "[", "<"].contains(подпись[номер].текст) { глубина += 1 }
            if [")", "]", ">"].contains(подпись[номер].текст), глубина > 0 { глубина -= 1 }
            if глубина == 0, подпись[номер].текст == "-", номер + 1 < подпись.count,
               подпись[номер + 1].текст == ">" { стрелка = номер; break }
        }
        if let стрелка { подпись = Array(подпись.prefix(стрелка)) }
        while let последнее = подпись.last, ["async", "throws"].contains(последнее.текст) { подпись.removeLast() }
        if подпись.first?.текст == "(", подпись.last?.текст == ")" {
            подпись.removeFirst(); подпись.removeLast()
        }
        if подпись.isEmpty { return }
        for сегмент in подпись.split(whereSeparator: { $0.текст == "," }) {
            let имена = сегмент.prefix(while: { $0.текст != ":" })
            guard имена.count == 1, let имя = имена.first, имя.имя else {
                throw отказ(слова[конец], "capture-list или сложная подпись замыкания")
            }
            результат.append(.init(имя: имя, вид: "параметр-замыкания", начальнаяСтрока: слова[начало].строка))
        }
    }

    private static func отказ(_ слово: ЛексемаЯзыковогоДопуска, _ причина: String) -> ОтказЯзыковогоДопуска {
        .неподдержанныйСинтаксис("\(слово.строка):\(слово.столбец): \(причина)")
    }
}

import Foundation

enum ОтображениеМанифеста {
    // Адаптер существующего fum.план-актуализации-путей.1, без данных владельцев.
    private struct Пара: Decodable { var исходный: String; var целевой: String }
    private struct Карта: Decodable {
        var схема: String
        var отображения: [Пара]
        var препятствия: [Препятствие]
        var применение_разрешено: Bool
        struct Препятствие: Decodable { var код: String; var пути: [String] }
    }

    static func применить(_ описание: ОписаниеПакета, карта: Data?, ожидаемыйХэш: String?,
                          исходники: [String], инвентарь: [String], корень: URL) throws -> ОписаниеПакета {
        guard let байты = карта else {
            try требоватьМанифест(ожидаемыйХэш == nil, "хэш-без-карты")
            return описание
        }
        try требоватьМанифест(ожидаемыйХэш == хэшМанифеста(байты), "неверный-хэш-карты")
        try СтрогоеОписаниеМанифеста.проверить(байты)
        let план = try JSONDecoder().decode(Карта.self, from: байты)
        try требоватьМанифест(план.схема == "fum.план-актуализации-путей.1"
            && план.препятствия.isEmpty && !план.применение_разрешено, "непригодная-карта")
        try ПроверкаМанифеста.уникальные(план.отображения.map(\.исходный))
        try ПроверкаМанифеста.уникальные(план.отображения.map(\.целевой))
        for пара in план.отображения {
            try ПутиМанифеста.проверить(пара.исходный); try ПутиМанифеста.проверить(пара.целевой)
        }
        let пары = план.отображения.sorted { $0.исходный.utf8.count > $1.исходный.utf8.count }
        func новый(_ путь: String) -> String {
            guard let пара = пары.first(where: { ПутиМанифеста.вложен(путь, в: $0.исходный) }) else { return путь }
            return пара.целевой + путь.dropFirst(пара.исходный.count)
        }
        // Проверяются и исключённые файлы; отсутствующая новая цепочка допустима.
        let будущийИнвентарь = инвентарь.map(новый)
        try ПроверкаМанифеста.уникальные(будущийИнвентарь)
        let чтение = try ЧитательПутейМанифеста(корень)
        for пара in пары {
            let существует = try чтение.проверитьНазначение(пара.целевой)
            if пара.исходный != пара.целевой && существует {
                try требоватьМанифест(try !чтение.каталог(пара.исходный), "существующее-назначение-каталога")
            }
        }
        for старый in инвентарь {
            let адрес = новый(старый)
            let существует = try чтение.проверитьНазначение(адрес)
            try требоватьМанифест(адрес == старый || !существует, "существующее-назначение-файла")
        }
        try требоватьМанифест(исходники.allSatisfy { новый($0).hasSuffix(".swift") }, "карта-теряет-swift-исходник")
        var результат = описание
        for номер in результат.цели.indices {
            let старая = описание.цели[номер].путь; let новая = новый(старая)
            func внутри(_ путь: String) throws -> String {
                let адрес = новый(старая + "/" + путь)
                try требоватьМанифест(адрес.hasPrefix(новая + "/"), "несогласованная-карта-цели")
                return String(адрес.dropFirst(новая.count + 1))
            }
            результат.цели[номер].путь = новая
            результат.цели[номер].исключения = try описание.цели[номер].исключения.map(внутри)
            результат.цели[номер].исходники = try описание.цели[номер].исходники.map { try $0.map(внутри) }
            результат.цели[номер].ресурсы = try описание.цели[номер].ресурсы.map { .init(вид: $0.вид, путь: try внутри($0.путь)) }
            for исходник in исходники.filter({ ПутиМанифеста.вложен($0, в: старая) }) {
                _ = try внутри(String(исходник.dropFirst(старая.count + 1)))
            }
        }
        for номер in результат.зависимости.indices { результат.зависимости[номер].путь = новый(описание.зависимости[номер].путь) }
        func границы(_ пакет: ОписаниеПакета) -> [String] {
            пакет.цели.flatMap { цель in
                [цель.путь] + (цель.исключения + (цель.исходники ?? []) + цель.ресурсы.map(\.путь))
                    .map { цель.путь + "/" + $0 }
            }
        }
        func однозначнаяГраница(_ левый: String, _ правый: String) throws {
            let ключЛевого = ПроверкаМанифеста.ключ(левый)
            let ключПравого = ПроверкаМанифеста.ключ(правый)
            try требоватьМанифест((!ПутиМанифеста.вложен(ключЛевого, в: ключПравого)
                    || ПутиМанифеста.вложен(левый, в: правый))
                && (!ПутиМанифеста.вложен(ключПравого, в: ключЛевого)
                    || ПутиМанифеста.вложен(правый, в: левый)), "неоднозначная-граница-карты")
        }
        let прежниеГраницы = границы(описание) + инвентарь
        let будущиеГраницы = границы(результат)
        for файл in будущийИнвентарь {
            for путь in будущиеГраницы { try однозначнаяГраница(файл, путь) }
        }
        // Целый прежний target tree доказывает покрытие префикса; отдельный файл — только себя.
        for пара in пары {
            for путь in прежниеГраницы { try однозначнаяГраница(пара.исходный, путь) }
            for путь in будущиеГраницы { try однозначнаяГраница(пара.целевой, путь) }
            for цель in результат.цели {
                let источник: String
                if ПутиМанифеста.вложен(пара.целевой, в: цель.путь) {
                    источник = пара.исходный
                } else if ПутиМанифеста.вложен(цель.путь, в: пара.целевой) {
                    источник = пара.исходный + цель.путь.dropFirst(пара.целевой.count)
                } else { continue }
                try требоватьМанифест(описание.цели.contains { ПутиМанифеста.вложен(источник, в: $0.путь) }
                    || инвентарь.contains(источник), "неполный-инвентарь-карты")
            }
        }
        let прежнийСостав = try ПроверкаМанифеста.составИсходников(описание, инвентарь: инвентарь)
        let будущийСостав = try ПроверкаМанифеста.составИсходников(результат, инвентарь: будущийИнвентарь)
        for номер in результат.цели.indices {
            try требоватьМанифест(Set(будущийСостав[номер]) == Set(прежнийСостав[номер].map(новый)),
                "карта-меняет-состав-исходников")
        }
        return результат
    }
}

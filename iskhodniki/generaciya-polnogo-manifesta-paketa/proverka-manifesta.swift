import Foundation

enum ПроверкаМанифеста {
    static func ключ(_ имя: String) -> String {
        имя.precomposedStringWithCanonicalMapping.folding(options: [.caseInsensitive], locale: Locale(identifier: "en_US_POSIX"))
    }
    static func уникальные(_ имена: [String]) throws {
        try требоватьМанифест(имена.allSatisfy { !$0.isEmpty && !$0.contains("\u{0000}") }
            && Set(имена.map(ключ)).count == имена.count, "дубль-или-коллизия")
    }
    static func идентификатор(_ имя: String) -> Bool {
        имя.range(of: #"\A[\p{L}_][\p{L}\p{N}_]*\z"#, options: .regularExpression) != nil
    }
    static func имяЦели(_ имя: String) -> Bool {
        имя.split(separator: "-", omittingEmptySubsequences: false)
            .allSatisfy { идентификатор(String($0)) }
    }

    static func структура(_ описание: ОписаниеПакета) throws {
        try требоватьМанифест(описание.схема == "fum.описание-пакета.1", "неизвестная-схема")
        try уникальные([описание.имя]); try уникальные(описание.цели.map(\.имя))
        try уникальные(описание.продукты.map(\.имя)); try уникальные(описание.зависимости.map(\.имя))
        try уникальные(описание.платформы.map { $0.платформа.rawValue })
        try требоватьМанифест(!описание.цели.isEmpty && !описание.платформы.isEmpty, "пустой-пакет")
        for платформа in описание.платформы {
            try требоватьМанифест(платформа.версия.range(of: #"\A[1-9][0-9]*(?:\.[0-9]+){0,2}\z"#, options: .regularExpression) != nil, "неверная-версия-платформы")
        }
        let цели = Dictionary(uniqueKeysWithValues: описание.цели.map { ($0.имя, $0) })
        let пакеты = Dictionary(uniqueKeysWithValues: описание.зависимости.map { ($0.имя, $0) })
        for пакет in описание.зависимости {
            try ПутиМанифеста.проверить(пакет.путь); try уникальные(пакет.продукты)
        }
        for цель in описание.цели {
            try требоватьМанифест(имяЦели(цель.имя), "неверное-имя-модуля")
            try ПутиМанифеста.проверить(цель.путь)
            try уникальные(цель.исключения); try уникальные(цель.исходники ?? [])
            try уникальные(цель.ресурсы.map(\.путь)); try уникальные(цель.определения)
            for путь in цель.исключения + (цель.исходники ?? []) + цель.ресурсы.map(\.путь) {
                try ПутиМанифеста.проверить(путь)
            }
            try требоватьМанифест(цель.определения.allSatisfy(идентификатор), "неверное-определение")
            var рёбра = Set<String>()
            for зависимость in цель.зависимости {
                if let имя = зависимость.цель {
                    try требоватьМанифест(зависимость.пакет == nil && зависимость.продукт == nil
                        && цели[имя] != nil && имя != цель.имя && цели[имя]?.вид != .проверочная, "неверная-зависимость-цели")
                    try требоватьМанифест(рёбра.insert("цель:" + имя).inserted, "повтор-ребра")
                } else {
                    guard let пакет = зависимость.пакет, let продукт = зависимость.продукт else {
                        throw ОшибкаМанифеста(код: "неполная-зависимость")
                    }
                    try требоватьМанифест(пакеты[пакет]?.продукты.contains(продукт) == true, "неразрешённый-продукт")
                    try требоватьМанифест(рёбра.insert("пакет:" + пакет + ":" + продукт).inserted, "повтор-ребра")
                }
            }
        }
        for продукт in описание.продукты {
            try уникальные(продукт.цели)
            try требоватьМанифест(!продукт.цели.isEmpty && продукт.цели.allSatisfy { цели[$0] != nil && цели[$0]?.вид != .проверочная }, "неверная-цель-продукта")
            if продукт.вид == .исполняемый {
                try требоватьМанифест(продукт.цели.count == 1 && цели[продукт.цели[0]]?.вид == .исполняемая, "неверный-исполняемый-продукт")
            } else {
                try требоватьМанифест(продукт.цели.allSatisfy { цели[$0]?.вид == .обычная }, "неверная-библиотека")
            }
        }
        var активные = Set<String>(); var готовые = Set<String>()
        func посетить(_ имя: String) throws {
            if готовые.contains(имя) { return }
            try требоватьМанифест(активные.insert(имя).inserted, "цикл-целей")
            for зависимость in цели[имя]!.зависимости { if let следующая = зависимость.цель { try посетить(следующая) } }
            активные.remove(имя); готовые.insert(имя)
        }
        for цель in описание.цели { try посетить(цель.имя) }
    }

    // Один выбор для физического и виртуального инвентаря; контракт sources не переписывается.
    static func исходники(_ цель: ЦельПакета, инвентарь: [String]) throws -> [String] {
        let все = инвентарь.filter { ПутиМанифеста.вложен($0, в: цель.путь) }
        var выбранные = все
        if let исходники = цель.исходники {
            выбранные = исходники.flatMap { путь in
                все.filter { ПутиМанифеста.вложен($0, в: цель.путь + "/" + путь) }
            }
            try требоватьМанифест(Set(выбранные).count == выбранные.count, "повтор-исходника")
            try требоватьМанифест(!выбранные.contains { файл in
                цель.исключения.contains { ПутиМанифеста.вложен(файл, в: цель.путь + "/" + $0) }
            }, "исходник-исключён")
        }
        let результат = выбранные.filter { файл in
            файл.hasSuffix(".swift") && !цель.исключения.contains { ПутиМанифеста.вложен(файл, в: цель.путь + "/" + $0) }
                && !цель.ресурсы.contains { ПутиМанифеста.вложен(файл, в: цель.путь + "/" + $0.путь) }
        }
        try требоватьМанифест(!результат.isEmpty, "нет-swift-исходников")
        return результат
    }

    static func составИсходников(_ описание: ОписаниеПакета, инвентарь: [String]) throws -> [[String]] {
        var занятые = Set<String>()
        return try описание.цели.map { цель in
            let выбранные = try исходники(цель, инвентарь: инвентарь)
            for файл in выбранные {
                try требоватьМанифест(занятые.insert(ключ(файл)).inserted, "пересечение-исходников")
            }
            return выбранные
        }
    }

    static func файлы(_ описание: ОписаниеПакета, корень: URL) throws -> (исходники: [String], все: [String]) {
        let чтение = try ЧитательПутейМанифеста(корень)
        var инвентарь = Set<String>()
        for пакет in описание.зависимости {
            try требоватьМанифест(try чтение.каталог(пакет.путь), "не-каталог-пакета")
            try требоватьМанифест(try !чтение.каталог(пакет.путь + "/Package.swift"), "нет-манифеста-зависимости")
            инвентарь.insert(пакет.путь + "/Package.swift")
        }
        for цель in описание.цели {
            try требоватьМанифест(try чтение.каталог(цель.путь), "не-каталог-цели")
            инвентарь.formUnion(try чтение.файлы(цель.путь))
            for путь in цель.исключения + (цель.исходники ?? []) + цель.ресурсы.map(\.путь) {
                _ = try чтение.каталог(цель.путь + "/" + путь)
            }
        }
        let все = инвентарь.sorted { $0.utf8.lexicographicallyPrecedes($1.utf8) }
        return (try составИсходников(описание, инвентарь: все).flatMap { $0 }, все)
    }
}

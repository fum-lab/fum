import Foundation

enum ПрофильМанифеста {
    private struct Замер: Codable {
        var стадия: String
        var повторов: Int
        var наносекунд: Int64
    }
    private struct Результат: Codable {
        var схема = "fum.профиль-порождения-манифеста.1"
        var отпечатокОписания: String
        var отпечатокМанифеста: String
        var замеры: [Замер]
        var граница = "Последовательные интервалы одного процесса; подготовка фикстуры и сборка вне таймера. Профиль локального примитива, не FUMA runtime."
    }

    static func измерить(_ данные: Data, корень: URL) throws -> Data {
        let описание = try ОписаниеПакета.прочитать(данные)
        let эталон = try ГенераторМанифеста.породить(описание, корень: корень).байты
        let часы = ContinuousClock()
        var замеры: [Замер] = []
        func серия(_ имя: String, _ действие: () throws -> Void) rethrows {
            let начало = часы.now
            for _ in 0..<100 { try действие() }
            let длительность = начало.duration(to: часы.now).components
            замеры.append(.init(стадия: имя, повторов: 100,
                наносекунд: длительность.seconds * 1_000_000_000 + длительность.attoseconds.quotientAndRemainder(dividingBy: 1_000_000_000).quotient))
        }
        try серия("декодирование") { try требоватьМанифест(ОписаниеПакета.прочитать(данные) == описание, "дрейф-json") }
        try серия("валидация-связей-и-файлов") {
            try ПроверкаМанифеста.структура(описание)
            _ = try ПроверкаМанифеста.файлы(описание, корень: корень)
        }
        try серия("чистое-порождение-байтов") { try требоватьМанифест(ГенераторМанифеста.текст(описание) == эталон, "дрейф-байтов") }
        try серия("полный-вызов") {
            try требоватьМанифест(ГенераторМанифеста.породить(описание, корень: корень).байты == эталон, "дрейф-полного-вызова")
        }
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(Результат(отпечатокОписания: хэшМанифеста(данные),
            отпечатокМанифеста: хэшМанифеста(эталон), замеры: замеры)) + Data([10])
    }
}

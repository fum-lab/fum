import Foundation
import FUMStructuringOperatorMemory

public enum ВалидаторМаршрутаПравил {
    public static func проверить(
        корень: URL,
        инвентарь путьИнвентаря: String = "Правила/агентов/инвентарь-правил.json",
        триггеры: [String],
        источник: ИсточникСнимкаПравил = .git
    ) throws -> РезультатМаршрутаПравил {
        let граница = try ГраницаCheckout(корень)
        let корневойURL = try граница.файл(
            "AGENTS.md", отсутствует: .отсутствуетМаршрутизатор)
        let inventoryURL = try граница.файл(
            путьИнвентаря, отсутствует: .отсутствуетИнвентарь)
        let корневойТекст = try прочитатьUTF8(
            корневойURL, категория: .отсутствуетМаршрутизатор)
        let inventoryData = try Data(contentsOf: inventoryURL)
        try ПроверкаЗакрытогоJSON.проверитьБезПовторов(inventoryData)
        let inventory: ИнвентарьПравил
        do {
            inventory = try JSONDecoder().decode(ИнвентарьПравил.self, from: inventoryData)
        } catch {
            throw ОтказМаршрутаПравил(.инвентарь, "Схема инвентаря не разобрана: \(error)")
        }
        guard inventory.схема == "fum.декомпозиция-правил-агентов.1" else {
            throw ОтказМаршрутаПравил(.инвентарь, "Неизвестная схема инвентаря")
        }

        let темы = try индексировать(inventory.темы, поле: "темы", ключ: \.идентификатор)
        var тексты: [String: String] = ["AGENTS.md": корневойТекст]
        var путиТем: Set<String> = []
        var историческиеПути: Set<String> = []
        for (_, тема) in темы {
            guard путиТем.insert(тема.путь).inserted, корректныйSHA256(тема.sha256Содержания) else {
                throw ОтказМаршрутаПравил(.инвентарь, "Повтор пути или неверный хэш темы")
            }
            let url = try граница.файл(тема.путь, отсутствует: .отсутствуетТема)
            let текст = try прочитатьUTF8(url, категория: .отсутствуетТема)
            let содержание = Data(содержаниеБезRecency(текст).utf8)
            guard хэшSHA256(содержание) == тема.sha256Содержания else {
                throw ОтказМаршрутаПравил(
                    .несовпадениеХэша, "Хэш темы \(тема.идентификатор) не совпадает")
            }
            if !тема.полномочия { историческиеПути.insert(тема.путь) }
            тексты[тема.путь] = текст
        }

        guard Set(inventory.служебныеПути).count == inventory.служебныеПути.count else {
            throw ОтказМаршрутаПравил(.инвентарь, "Служебный путь повторён")
        }
        for путь in inventory.служебныеПути {
            _ = try граница.файл(путь, отсутствует: .инвентарь)
        }

        let исходныеБайты = try ЗагрузкаИсходногоСнимка.загрузить(
            inventory.исходныйСнимок, корень: граница.корень, источник: источник)
        let исходные = try проверитьИсходныеЕдиницы(
            inventory.исходныеЕдиницы,
            снимок: исходныеБайты,
            заявленоБайтов: inventory.исходныйСнимок.байтов)
        try проверитьМаркерыИПокрытие(
            правила: inventory.правила, исходные: исходные,
            тексты: тексты, путиТем: путиТем,
            историческиеПути: историческиеПути, граница: граница)

        let проекция = ПроекцияМаршрутизации(
            схема: "fum.проекция-маршрутизации-правил.1",
            маршруты: inventory.маршруты,
            фикстуры: inventory.фикстуры)
        let fumaПроекция = try провестиЧерезFUMA(проекция)
        let карта = try проверитьМаршруты(
            fumaПроекция,
            путиТем: путиТем,
            служебныеПути: Set(inventory.служебныеПути),
            историческиеПути: историческиеПути,
            корневойТекст: корневойТекст)

        for триггер in триггеры where карта[триггер] == nil {
            throw ОтказМаршрутаПравил(
                .неизвестныйТриггер, "Неизвестный триггер \(триггер)")
        }
        let пути = Set(триггеры.flatMap { карта[$0] ?? [] })
        return РезультатМаршрутаПравил(пути: сортироватьБайтами(пути))
    }

    private static func проверитьИсходныеЕдиницы(
        _ элементы: [ИсходнаяЕдиница],
        снимок: Data,
        заявленоБайтов: Int
    ) throws -> [String: ИсходнаяЕдиница] {
        let индекс = try индексировать(
            элементы, поле: "исходные_единицы", ключ: \.идентификатор)
        var диапазоны: Set<String> = []
        for элемент in элементы {
            guard элемент.номерСтроки > 0, !элемент.класс.isEmpty,
                  элемент.началоБайта >= 0,
                  элемент.конецБайта > элемент.началоБайта,
                  элемент.конецБайта <= заявленоБайтов,
                  корректныйSHA256(элемент.sha256) else {
                throw ОтказМаршрутаПравил(.покрытие, "Некорректная исходная единица")
            }
            let ключ = "\(элемент.началоБайта):\(элемент.конецБайта)"
            guard диапазоны.insert(ключ).inserted else {
                throw ОтказМаршрутаПравил(.покрытие, "Диапазон исходника повторён")
            }
            let срез = Data(снимок[элемент.началоБайта..<элемент.конецБайта])
            guard хэшSHA256(срез) == элемент.sha256 else {
                throw ОтказМаршрутаПравил(.несовпадениеХэша, "Хэш диапазона исходника не совпадает")
            }
        }
        var ожидаемоеНачало = 0
        for элемент in элементы.sorted(by: {
            ($0.началоБайта, $0.конецБайта) < ($1.началоБайта, $1.конецБайта)
        }) {
            guard элемент.началоБайта == ожидаемоеНачало else {
                throw ОтказМаршрутаПравил(.покрытие, "Разрыв или перекрытие исходного inventory")
            }
            ожидаемоеНачало = элемент.конецБайта
        }
        guard ожидаемоеНачало == заявленоБайтов else {
            throw ОтказМаршрутаПравил(.покрытие, "Исходный inventory не покрывает снимок")
        }
        return индекс
    }

    private static func проверитьМаркерыИПокрытие(
        правила: [ЗарегистрированноеПравило],
        исходные: [String: ИсходнаяЕдиница],
        тексты: [String: String],
        путиТем: Set<String>,
        историческиеПути: Set<String>,
        граница: ГраницаCheckout
    ) throws {
        let индекс = try индексировать(правила, поле: "правила", ключ: \.идентификатор)
        let допустимыеСтатусы: Set<String> = [
            "действует", "история", "исчерпано", "контекст", "происхождение",
        ]
        let историческиеСтатусы: Set<String> = ["история", "исчерпано", "происхождение"]
        var активныеСемантическиеКлючи: Set<String> = []
        var использовано: [String: Int] = [:]
        for правило in правила {
            guard допустимыеСтатусы.contains(правило.статус), !правило.приоритет.isEmpty,
                  !правило.области.isEmpty, !правило.триггеры.isEmpty,
                  !правило.семантическийКлюч.isEmpty,
                  правило.назначение.якорь == правило.идентификатор,
                  let текст = тексты[правило.назначение.путь] else {
                throw ОтказМаршрутаПравил(.инвентарь, "Некорректные поля правила")
            }
            let маркер = "<!-- FUM-ПРАВИЛО: \(правило.идентификатор) -->"
            guard точныеСтроки(текст, равные: маркер) == 1 else {
                throw ОтказМаршрутаПравил(.маркер, "Маркер правила не уникален или неточен")
            }
            if правило.источники.isEmpty {
                guard let основание = правило.новоеОснование, !основание.isEmpty else {
                    throw ОтказМаршрутаПравил(
                        .инвентарь, "Правило не имеет источников или нового основания")
                }
                _ = try граница.файл(основание, отсутствует: .инвентарь)
            }
            for источник in правило.источники {
                guard let единица = исходные[источник], единица.требуетПравило ?? true else {
                    throw ОтказМаршрутаПравил(.покрытие, "Правило ссылается на неизвестный источник")
                }
                использовано[источник, default: 0] += 1
            }
            if правило.статус == "действует" {
                guard !историческиеПути.contains(правило.назначение.путь) else {
                    throw ОтказМаршрутаПравил(
                        .инвентарь, "Активная норма находится в теме без полномочий")
                }
                guard активныеСемантическиеКлючи.insert(
                    правило.семантическийКлюч).inserted else {
                    throw ОтказМаршрутаПравил(
                        .инвентарь, "Семантический ключ активного правила повторён")
                }
            } else if путиТем.contains(правило.назначение.путь),
                      !историческиеПути.contains(правило.назначение.путь),
                      историческиеСтатусы.contains(правило.статус) {
                throw ОтказМаршрутаПравил(
                    .инвентарь, "Исторический статус находится в активной теме")
            }
        }
        for (путь, текст) in тексты {
            for идентификатор in точныеМаркерыПравил(текст) {
                guard let правило = индекс[идентификатор],
                      Data(правило.назначение.путь.utf8) == Data(путь.utf8) else {
                    throw ОтказМаршрутаПравил(.маркер, "Незарегистрированный или перемещённый маркер")
                }
            }
        }
        let обязательные = Set(исходные.values.filter { $0.требуетПравило ?? true }.map(\.идентификатор))
        guard Set(использовано.keys) == обязательные,
              использовано.values.allSatisfy({ $0 == 1 }) else {
            throw ОтказМаршрутаПравил(
                .покрытие, "Обязательный исходный inventory покрыт не полностью или неоднозначно")
        }
    }

    private static func провестиЧерезFUMA(
        _ проекция: ПроекцияМаршрутизации
    ) throws -> ПроекцияМаршрутизации {
        guard let url = Bundle.module.url(
            forResource: "proveritj-marshrut", withExtension: "json",
            subdirectory: "opredeleniya") else {
            throw ОтказМаршрутаПравил(.инвентарь, "FUMA-оператор маршрута отсутствует")
        }
        do {
            let определение = try ОпределениеОператора.разобрать(Data(contentsOf: url))
            guard определение.идентификатор == "fum.проверить-маршрут-правил",
                  определение.версия == 1, определение.шаги.count == 1,
                  case .вычислитьJSON = определение.шаги[0].действие else {
                throw ОтказМаршрутаПравил(.инвентарь, "FUMA-оператор маршрута подменён")
            }
            let encoder = JSONEncoder()
            encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
            let данные = try encoder.encode(проекция)
            guard let текст = String(data: данные, encoding: .utf8) else {
                throw ОтказМаршрутаПравил(.инвентарь, "Проекция маршрута не UTF-8")
            }
            let исполнение = try AutomationExecutor.выполнить(
                определение, вход: .текст(текст))
            guard case .текст(let результат) = исполнение.результат else {
                throw ОтказМаршрутаПравил(.инвентарь, "FUMA вернула иной тип")
            }
            let декодировано = try JSONDecoder().decode(
                ПроекцияМаршрутизации.self, from: Data(результат.utf8))
            guard декодировано == проекция else {
                throw ОтказМаршрутаПравил(.инвентарь, "FUMA изменила проекцию маршрута")
            }
            return декодировано
        } catch let отказ as ОтказМаршрутаПравил {
            throw отказ
        } catch {
            throw ОтказМаршрутаПравил(.инвентарь, "FUMA отказала: \(error)")
        }
    }

    private static func проверитьМаршруты(
        _ проекция: ПроекцияМаршрутизации,
        путиТем: Set<String>,
        служебныеПути: Set<String>,
        историческиеПути: Set<String>,
        корневойТекст: String
    ) throws -> [String: [String]] {
        guard проекция.схема == "fum.проекция-маршрутизации-правил.1" else {
            throw ОтказМаршрутаПравил(.инвентарь, "Схема проекции маршрута неверна")
        }
        let маршруты = try индексировать(
            проекция.маршруты, поле: "маршруты", ключ: \.идентификатор)
        let допустимые = путиТем.union(служебныеПути)
        var карта: [String: [String]] = [:]
        for (идентификатор, маршрут) in маршруты {
            let пути = Set(маршрут.пути)
            guard пути.count == маршрут.пути.count, пути.isSubset(of: допустимые) else {
                throw ОтказМаршрутаПравил(.инвентарь, "Маршрут содержит повтор или неизвестный путь")
            }
            if идентификатор != "правила", !пути.isDisjoint(with: историческиеПути) {
                throw ОтказМаршрутаПравил(.инвентарь, "Исторический файл даёт полномочия")
            }
            карта[идентификатор] = маршрут.пути
        }
        guard Set(карта["правила"] ?? []) == допустимые else {
            throw ОтказМаршрутаПравил(.инвентарь, "Маршрут правил не покрывает реестр")
        }
        let корневые = try разобратьКорневыеМаршруты(корневойТекст)
        let rootSets = корневые.mapValues(Set.init)
        let inventorySets = карта.mapValues(Set.init)
        guard rootSets == inventorySets else {
            throw ОтказМаршрутаПравил(.маркер, "Корневые маркеры маршрутов не совпадают с реестром")
        }
        for фикстура in проекция.фикстуры {
            guard !фикстура.идентификатор.isEmpty, !фикстура.триггеры.isEmpty,
                  Set(фикстура.триггеры).count == фикстура.триггеры.count,
                  фикстура.триггеры.allSatisfy({ карта[$0] != nil }) else {
                throw ОтказМаршрутаПравил(.фикстураМаршрутизации, "Некорректная фикстура")
            }
            let фактические = Set(фикстура.триггеры.flatMap { карта[$0] ?? [] })
            guard фактические == Set(фикстура.ожидаемыеПути),
                  Set(фикстура.ожидаемыеПути).count == фикстура.ожидаемыеПути.count else {
                throw ОтказМаршрутаПравил(
                    .фикстураМаршрутизации, "Безопасное объединение фикстуры не совпадает")
            }
        }
        return карта
    }

    private static func разобратьКорневыеМаршруты(_ текст: String) throws -> [String: [String]] {
        let prefix = "<!-- FUM-МАРШРУТ: "
        let suffix = " -->"
        var результат: [String: [String]] = [:]
        for строка in текст.components(separatedBy: "\n")
        where строка.hasPrefix(prefix) && строка.hasSuffix(suffix) {
            let начало = строка.index(строка.startIndex, offsetBy: prefix.count)
            let конец = строка.index(строка.endIndex, offsetBy: -suffix.count)
            let тело = String(строка[начало..<конец])
            guard let раздел = тело.range(of: " =>"),
                  тело.range(of: " =>", range: раздел.upperBound..<тело.endIndex) == nil else {
                throw ОтказМаршрутаПравил(.маркер, "Неточный маркер маршрута")
            }
            let идентификатор = String(тело[..<раздел.lowerBound])
            let сырыеПути = String(тело[раздел.upperBound...]).trimmingCharacters(in: .whitespaces)
            guard !идентификатор.isEmpty, !идентификатор.contains(" "),
                  результат[идентификатор] == nil else {
                throw ОтказМаршрутаПравил(.маркер, "Повтор или пустой идентификатор маршрута")
            }
            let пути = сырыеПути.isEmpty ? [] : сырыеПути.split(
                separator: ";", omittingEmptySubsequences: false
            ).map { $0.trimmingCharacters(in: .whitespaces) }
            guard пути.allSatisfy({ !$0.isEmpty }), Set(пути).count == пути.count else {
                throw ОтказМаршрутаПравил(.маркер, "Пустой или повторённый путь маршрута")
            }
            результат[идентификатор] = пути
        }
        return результат
    }

    private static func индексировать<T>(
        _ элементы: [T],
        поле: String,
        ключ: KeyPath<T, String>
    ) throws -> [String: T] {
        var результат: [String: T] = [:]
        for элемент in элементы {
            let идентификатор = элемент[keyPath: ключ]
            guard !идентификатор.isEmpty, результат[идентификатор] == nil else {
                throw ОтказМаршрутаПравил(.инвентарь, "\(поле): идентификатор повторён или пуст")
            }
            результат[идентификатор] = элемент
        }
        return результат
    }

    private static func прочитатьUTF8(
        _ url: URL,
        категория: ОтказМаршрутаПравил.Категория
    ) throws -> String {
        do {
            let данные = try Data(contentsOf: url)
            guard let текст = String(data: данные, encoding: .utf8) else {
                throw ОтказМаршрутаПравил(категория, "Файл не UTF-8")
            }
            return текст
        } catch let отказ as ОтказМаршрутаПравил {
            throw отказ
        } catch {
            throw ОтказМаршрутаПравил(категория, "Файл не читается")
        }
    }

    private static func точныеСтроки(_ текст: String, равные образец: String) -> Int {
        текст.components(separatedBy: "\n").filter { $0 == образец }.count
    }

    private static func точныеМаркерыПравил(_ текст: String) -> [String] {
        let prefix = "<!-- FUM-ПРАВИЛО: "
        let suffix = " -->"
        return текст.components(separatedBy: "\n").compactMap { строка in
            guard строка.hasPrefix(prefix), строка.hasSuffix(suffix) else { return nil }
            let начало = строка.index(строка.startIndex, offsetBy: prefix.count)
            let конец = строка.index(строка.endIndex, offsetBy: -suffix.count)
            return String(строка[начало..<конец])
        }
    }

    private static func сортироватьБайтами(_ значения: Set<String>) -> [String] {
        значения.sorted {
            Array($0.utf8).lexicographicallyPrecedes(Array($1.utf8))
        }
    }
}

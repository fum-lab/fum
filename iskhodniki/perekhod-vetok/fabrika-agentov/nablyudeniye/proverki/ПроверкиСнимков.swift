private extension ДанныеПроверок {
  static func ожидаемыйУзел(номер: Int) throws -> ОжидаемыйУзел {
    guard let result = UUID(uuidString: String(format: "00000000-0000-0000-0000-%012d", номер)) else {
      throw ОшибкаСнимка.неверныйИдентификатор
    }
    return ожидаемыйУзел(идентификатор: .поток(result, hostID: "local"))
  }

  static func ожидаемыйУзел(идентификатор: УзелНаблюдения) -> ОжидаемыйУзел {
    let кореньУзла = УзелНаблюдения.поток(корень, hostID: "local")
    let предки = идентификатор == кореньУзла ? [] : [кореньУзла]
    return ОжидаемыйУзел(
      идентификатор: идентификатор, репозиторий: "fum-lab/fum", корень: корень,
      родитель: идентификатор == кореньУзла ? nil : кореньУзла,
      предки: предки, линияИзвестна: true)
  }
}

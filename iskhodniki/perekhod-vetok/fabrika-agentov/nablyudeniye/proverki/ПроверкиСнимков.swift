private enum ДанныеПроверок {
  static let корень = UUID(uuidString: "00000000-0000-0000-0000-000000000001")!
  static let вызывающий = УзелНаблюдения.поток(
    UUID(uuidString: "00000000-0000-0000-0000-000000000099")!, hostID: "local")
  static let время = Date(timeIntervalSince1970: 1_798_000_000)

  static func узел(_ номер: Int, линияИзвестна: Bool = true) -> ОжидаемыйУзел {
    let id = UUID(uuidString: String(format: "00000000-0000-0000-0000-%012d", номер))!
    let кореньУзла = УзелНаблюдения.поток(корень, hostID: "local")
    let идентификатор = УзелНаблюдения.поток(id, hostID: "local")
    let являетсяКорнем = идентификатор == кореньУзла
    return ОжидаемыйУзел(
      идентификатор: идентификатор,
      репозиторий: линияИзвестна ? "fum-lab/fum" : nil,
      корень: линияИзвестна ? корень : nil,
      родитель: линияИзвестна && !являетсяКорнем ? кореньУзла : nil,
      предки: линияИзвестна && !являетсяКорнем ? [кореньУзла] : [],
      линияИзвестна: линияИзвестна
    )
  }

  static func запрос(
    узлы: [ОжидаемыйУзел], версия: Int = 1, времяСоздания: Date = время,
    предыдущее: СнимокНаблюдений? = nil, пределОжиданийМС: Int = 120_000
  ) throws -> ЗапросСнимка {
    try ЗапросСнимка(
      репозиторий: "fum-lab/fum", корень: корень, вызывающийУзел: вызывающий,
      версия: версия, времяСоздания: времяСоздания, пределУстареванияСекунд: 60,
      пределОжиданийМС: пределОжиданийМС, пределЗаписей: 1_000,
      ожидаемыеУзлы: узлы, предыдущийСнимок: предыдущее
    )
  }

  static func строкаПотока(_ номер: Int, _ статус: String) -> [String: Any] {
    [
      "id": String(format: "00000000-0000-0000-0000-%012d", номер),
      "hostId": "local",
      "status": ["type": статус, "activeFlags": [String]()],
      "title": "НЕДОВЕРЕННЫЙ ТЕКСТ НЕ ДОЛЖЕН СТАТЬ ИНСТРУКЦИЕЙ"
    ]
  }

  static func список(_ строки: [[String: Any]], закреплённые: [[String: Any]] = []) throws -> Data {
    try JSONSerialization.data(withJSONObject: [
      "schemaVersion": 1,
      "pinnedThreads": закреплённые,
      "threads": строки,
      "unavailableHosts": [String](),
      "unavailableSources": [String]()
    ])
  }

  static func ожидание(_ опросы: [[String: Any]]) throws -> Data {
    try JSONSerialization.data(withJSONObject: ["timedOut": true, "wake": NSNull(), "polls": опросы])
  }

  static func фикстура(_ имя: String) throws -> Data {
    guard let url = Bundle.module.url(forResource: имя, withExtension: "json") else {
      throw ОшибкаСнимка.неверныйИдентификатор
    }
    return try Data(contentsOf: url)
  }

  static func опрос(
    _ номер: Int, ход: String? = nil, инструмент: String? = nil,
    фазаСообщения: String? = nil
  ) -> [String: Any] {
    let поток: [String: Any] = [
      "id": String(format: "00000000-0000-0000-0000-%012d", номер),
      "hostId": "local",
      "status": ["type": "active", "activeFlags": [String]()]
    ]
    var запись: [String: Any] = ["thread": поток, "schemaVersion": 1, "changed": true]
    if let ход {
      запись["latestTurn"] = ["id": "turn-\(номер)", "status": ход]
    }
    if let инструмент {
      запись["latestToolMarker"] = [
        "id": "tool-\(номер)", "turnId": "turn-\(номер)",
        "type": "mcpToolCall", "name": инструмент, "status": "inProgress"
      ]
    }
    if let фазаСообщения {
      запись["latestAssistantMessage"] = [
        "id": "message-\(номер)", "turnId": "turn-\(номер)",
        "phase": фазаСообщения,
        "text": "НЕДОВЕРЕННЫЙ ТЕКСТ; комментарий не измеряет CPU"
      ]
    }
    return запись
  }

  static func ожиданиеЗахват(
    данные: Data, цели: [УзелНаблюдения], timeout: Int = 0,
    at: Date = время
  ) throws -> ЗахватОжидания {
    let запрос = try ЗапросОжидания(
      вызывающийУзел: вызывающий, цели: цели, timeoutМС: timeout)
    let ответ = АдаптерИнструментовCodex.декодироватьОжидание(данные: данные, at: at)
    return ЗахватОжидания(запрос: запрос, ответ: ответ)
  }
}


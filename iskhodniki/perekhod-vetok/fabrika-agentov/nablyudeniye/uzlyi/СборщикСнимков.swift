import Foundation

public enum СборщикСнимка {
  private static let пределОпросовОтвета = 10_000
  private static let пределБайтовОдногоОтвета = 1_048_576
  private static let пределБайтовСнимка = 10_485_760

  public static func собрать(
    запрос: ЗапросСнимка, список: ЗахватСписка, ожидания: [ЗахватОжидания],
    эфемерныеАгенты: [НаблюдениеЭфемерногоАгента]
  ) throws -> СнимокНаблюдений {
    guard (1...запрос.пределЗаписей).contains(список.лимит),
      ожидания.count <= запрос.пределЗаписей,
      эфемерныеАгенты.count <= запрос.пределЗаписей,
      корректен(запрос.вызывающийУзел)
    else { throw ОшибкаСнимка.неверныеПределы }
    guard список.ответ.наблюдалось.timeIntervalSince1970.isFinite else {
      throw ОшибкаСнимка.неверныеПределы
    }

    var счётчики = ЧерновикСчётчиков()
    var черновики: [УзелНаблюдения: ЧерновикЗаписи] = [:]
    черновики.reserveCapacity(запрос.ожидаемыеУзлы.count)

    for ожидаемый in запрос.ожидаемыеУзлы {
      try прибавить(1, к: &счётчики.ожидаемыхУзлов)
      if ожидаемый.линияИзвестна {
        try учестьСвязи(ожидаемый.предки.count, для: запрос, в: &счётчики)
        if ожидаемый.родитель != nil {
          try учестьСвязи(1, для: запрос, в: &счётчики)
        }
      }
      guard корректен(ожидаемый.идентификатор) else {
        throw ОшибкаСнимка.неверныйИдентификатор
      }
      if ожидаемый.линияИзвестна,
        !корректнаЛиния(
          идентификатор: ожидаемый.идентификатор, репозиторий: ожидаемый.репозиторий,
          корень: ожидаемый.корень, родитель: ожидаемый.родитель,
          предки: ожидаемый.предки, репозиторийЗапроса: запрос.репозиторий,
          кореньЗапроса: запрос.корень)
      {
        throw ОшибкаСнимка.невернаяЛиния
      }
      guard черновики[ожидаемый.идентификатор] == nil else {
        throw ОшибкаСнимка.повторОжидаемогоУзла
      }
      черновики[ожидаемый.идентификатор] = ЧерновикЗаписи(ожидаемый: ожидаемый)
    }

    var доступныеБайты = 0
    try учестьБайты(список.ответ.доступныеБайты, в: &доступныеБайты)
    let доступностьСписка = эффективнаяДоступность(
      список.ответ.доступность, байты: список.ответ.доступныеБайты)
    let списокДоступен = доступностьСписка == .доступно
      && список.ответ.значение != nil
    var достигнутЛимитОбычногоСписка = false
    var пропущеноХостов = 0
    var пропущеноИсточников = списокДоступен ? 0 : 1
    var валидныхИсточников = списокДоступен ? 1 : 0
    var неверныхИдентификаторов = 0
    var неверныхОпросов = 0
    var строкВнеОбласти = 0
    var неадресныхОпросов = 0
    var пустыхСнимковОжидания = 0
    var истеклоОжиданий = 0
    var ошибокОжиданий = 0

    if списокДоступен, let ответ = список.ответ.значение {
      guard let закреплённые = ответ.закреплённыеПотоки,
        let обычные = ответ.обычныеПотоки,
        закреплённые.count <= запрос.пределЗаписей,
        обычные.count <= запрос.пределЗаписей
      else { throw ОшибкаСнимка.превышенПределЗаписей }

      достигнутЛимитОбычногоСписка = обычные.count >= список.лимит
      пропущеноХостов = ответ.числоНедоступныхХостов ?? 0
      пропущеноИсточников += ответ.числоНедоступныхИсточников ?? 0

      for (строки, источник) in [
        (закреплённые, ИсточникЗаписи.закреплённыйСписокПотоков),
        (обычные, ИсточникЗаписи.обычныйСписокПотоков)
      ] {
        for строка in строки {
          try прибавить(1, к: &счётчики.строкСписка)
          guard let идентификатор = идентификаторПотока(строка) else {
            try прибавить(1, к: &неверныхИдентификаторов)
            continue
          }
          guard let черновик = черновики[идентификатор] else {
            try прибавить(1, к: &строкВнеОбласти)
            continue
          }
          черновик.добавитьСвидетельство(
            источник: источник, наблюдалось: список.ответ.наблюдалось,
            версия: запрос.версия, текущее: true)
          добавитьСтатусAPI(строка.статус, в: черновик)
        }
      }
    }

    var суммарноеОкноОжиданий = 0
    var всегоЦелейОжидания = 0
    var всегоОпросов = 0
    var доступностиОжиданий: [ДоступностьОтвета] = []
    доступностиОжиданий.reserveCapacity(ожидания.count)
    for захват in ожидания {
      guard захват.ответ.наблюдалось.timeIntervalSince1970.isFinite else {
        throw ОшибкаСнимка.неверныеПределы
      }
      guard захват.запрос.вызывающийУзел == запрос.вызывающийУзел else {
        throw ОшибкаСнимка.неверныйИдентификатор
      }
      let (новоеОкно, переполнениеОкна) = суммарноеОкноОжиданий
        .addingReportingOverflow(захват.запрос.timeoutМС)
      guard !переполнениеОкна, новоеОкно <= запрос.пределОжиданийМС else {
        throw ОшибкаСнимка.превышенПределОжиданий
      }
      суммарноеОкноОжиданий = новоеОкно
      let (новоеЧислоЦелей, переполнениеЦелей) = всегоЦелейОжидания
        .addingReportingOverflow(захват.запрос.цели.count)
      guard !переполнениеЦелей, новоеЧислоЦелей <= запрос.пределЗаписей else {
        throw ОшибкаСнимка.превышенПределОжиданий
      }
      всегоЦелейОжидания = новоеЧислоЦелей
      let числоОпросов = захват.ответ.значение?.опросы?.count ?? 0
      let (новоеЧислоОпросов, переполнениеОпросов) = всегоОпросов
        .addingReportingOverflow(числоОпросов)
      guard !переполнениеОпросов, новоеЧислоОпросов <= пределОпросовОтвета else {
        throw ОшибкаСнимка.превышенПределЗаписей
      }
      всегоОпросов = новоеЧислоОпросов
      try учестьБайты(захват.ответ.доступныеБайты, в: &доступныеБайты)
      var цели = Set<УзелНаблюдения>()
      цели.reserveCapacity(захват.запрос.цели.count)
      for цель in захват.запрос.цели {
        try прибавить(1, к: &счётчики.целейОжидания)
        guard корректен(цель), цель.вид == .поток else {
          throw ОшибкаСнимка.неверныйИдентификатор
        }
        цели.insert(цель)
        if черновики[цель] == nil {
          try прибавить(1, к: &строкВнеОбласти)
        }
      }
      let доступностьОжидания = эффективнаяДоступность(
        захват.ответ.доступность, байты: захват.ответ.доступныеБайты)
      доступностиОжиданий.append(доступностьОжидания)
      guard доступностьОжидания == .доступно,
        let ответ = захват.ответ.значение,
        let опросы = ответ.опросы
      else {
        try прибавить(1, к: &пропущеноИсточников)
        continue
      }
      try прибавить(1, к: &валидныхИсточников)
      if ответ.истеклоВремя == true {
        try прибавить(1, к: &истеклоОжиданий)
      }
      if опросы.isEmpty {
        try прибавить(1, к: &пустыхСнимковОжидания)
      }
      let числоОшибок = ответ.числоОшибок ?? 0
      guard числоОшибок >= 0 else { throw ОшибкаСнимка.неверныеПределы }
      try прибавить(числоОшибок, к: &ошибокОжиданий)
      try прибавить(числоОшибок, к: &пропущеноИсточников)

      for опрос in опросы {
        try прибавить(1, к: &счётчики.опросов)
        guard опрос.версияСхемы == 1 else {
          try прибавить(1, к: &неверныхОпросов)
          continue
        }
        guard let поток = опрос.поток,
          let идентификатор = идентификаторПотока(поток)
        else {
          try прибавить(1, к: &неверныхИдентификаторов)
          continue
        }
        guard цели.contains(идентификатор) else {
          try прибавить(1, к: &неадресныхОпросов)
          continue
        }
        guard let черновик = черновики[идентификатор] else {
          try прибавить(1, к: &строкВнеОбласти)
          continue
        }
        черновик.добавитьСвидетельство(
          источник: .ограниченноеОжиданиеПотоков,
          наблюдалось: захват.ответ.наблюдалось, версия: запрос.версия, текущее: true)
        добавитьСтатусAPI(поток.статус, в: черновик)
        if let статусХода = опрос.последнийХод?.статус {
          черновик.состоянияХода.insert(статусХода)
          добавитьСмысловойСтатус(
            статусХода, разрешитьВыполнение: true, в: &черновик.статусы)
        }
        if let ход = опрос.последнийХод, ход.статус == "inProgress",
          let ходID = ход.id,
          let фазаСообщения = опрос.последнееСообщение,
          фазаСообщения.ходID == ходID,
          фазаСообщения.фаза == "analysis" || фазаСообщения.фаза == "final"
        {
          черновик.статусы.insert(.содержательнаяРабота)
        }
        if let маркер = опрос.последнийИнструмент {
          if являетсяОпросомПотоков(маркер.имя) && маркер.статус == "inProgress" {
            черновик.статусы.insert(.ожиданиеДочернегоУзла)
          } else if let статус = маркер.статус,
            статус == "failed" || являетсяЁмкостнымОграничением(статус)
          {
            добавитьСмысловойСтатус(статус, в: &черновик.статусы)
          }
        }
      }
    }

    for агент in эфемерныеАгенты {
      guard агент.наблюдалось.timeIntervalSince1970.isFinite else {
        throw ОшибкаСнимка.неверныеПределы
      }
      try прибавить(1, к: &счётчики.эфемерныхАгентов)
      try учестьБайты(агент.доступныеБайты, в: &доступныеБайты)
      try учестьСвязи(агент.предки.count, для: запрос, в: &счётчики)
      if агент.родитель != nil {
        try учестьСвязи(1, для: запрос, в: &счётчики)
      }
      guard корректен(агент.идентификатор), агент.идентификатор.вид == .эфемерныйАгент,
        агент.состояние.utf8.count <= 128,
        let репозиторий = агент.репозиторий, let корень = агент.корень,
        корректнаЛиния(
          идентификатор: агент.идентификатор, репозиторий: репозиторий,
          корень: корень, родитель: агент.родитель, предки: агент.предки,
          репозиторийЗапроса: запрос.репозиторий, кореньЗапроса: запрос.корень)
      else {
        try прибавить(1, к: &строкВнеОбласти)
        continue
      }
      guard let черновик = черновики[агент.идентификатор] else {
        try прибавить(1, к: &строкВнеОбласти)
        continue
      }
      var совпадаетЛиния = true
      if черновик.линияИзвестна {
        совпадаетЛиния = черновик.репозиторий == репозиторий
          && черновик.корень == корень && черновик.родитель == агент.родитель
          && черновик.предки.count == агент.предки.count
        if совпадаетЛиния {
          for индекс in черновик.предки.indices {
            try учестьСвязи(1, для: запрос, в: &счётчики)
            if черновик.предки[индекс] != агент.предки[индекс] {
              совпадаетЛиния = false
              break
            }
          }
        }
      }
      if !совпадаетЛиния {
        try прибавить(1, к: &строкВнеОбласти)
        continue
      }
      if !черновик.линияИзвестна {
        черновик.репозиторий = репозиторий
        черновик.корень = корень
        черновик.родитель = агент.родитель
        черновик.предки = агент.предки
        черновик.линияИзвестна = true
      }
      черновик.добавитьСвидетельство(
        источник: .эфемерныйАгент, наблюдалось: агент.наблюдалось,
        версия: запрос.версия, текущее: true)
      черновик.состоянияАгента.insert(агент.состояние)
      добавитьСмысловойСтатус(
        агент.состояние, разрешитьВыполнение: true, в: &черновик.статусы)
    }

    if let предыдущийСнимок = запрос.предыдущийСнимок {
      guard предыдущийСнимок.записи.count <= запрос.пределЗаписей else {
        throw ОшибкаСнимка.превышенПределЗаписей
      }
      for стараяЗапись in предыдущийСнимок.записи {
        try прибавить(1, к: &счётчики.предыдущихЗаписей)
        guard корректен(стараяЗапись.идентификатор),
          стараяЗапись.наблюдалось.timeIntervalSince1970.isFinite,
          стараяЗапись.статусы.count <= СмысловойСтатус.allCases.count,
          стараяЗапись.предыдущиеСтатусы.count <= СмысловойСтатус.allCases.count
        else { throw ОшибкаСнимка.неверныйИдентификатор }
        guard let черновик = черновики[стараяЗапись.идентификатор] else { continue }
        черновик.предыдущиеСтатусы.formUnion(стараяЗапись.статусы)
        черновик.предыдущиеСтатусы.formUnion(стараяЗапись.предыдущиеСтатусы)
        черновик.добавитьСвидетельство(
          источник: .предыдущийСнимок, наблюдалось: стараяЗапись.наблюдалось,
          версия: стараяЗапись.версия, текущее: false)
      }
    }

    var записи: [ЗаписьСнимка] = []
    var недостающие: [УзелНаблюдения] = []
    var естьСбойИлиОграничениеЁмкости = false
    var естьУзлыСНеизвестнойЛинией = false
    записи.reserveCapacity(черновики.count)
    for ожидаемый in запрос.ожидаемыеУзлы {
      guard let черновик = черновики[ожидаемый.идентификатор] else {
        throw ОшибкаСнимка.неверныйИдентификатор
      }
      if !черновик.линияИзвестна { естьУзлыСНеизвестнойЛинией = true }
      if черновик.текущихНаблюдений == 0 {
        недостающие.append(ожидаемый.идентификатор)
      }
      if черновик.статусы.isEmpty {
        черновик.статусы.insert(.неизвестно)
      }
      if обнаруженКонфликт(черновик.статусы, черновик: черновик) {
        черновик.статусы.insert(.конфликт)
      }
      if черновик.статусы.contains(.сбой) || черновик.статусы.contains(.ограниченЁмкостью) {
        естьСбойИлиОграничениеЁмкости = true
      }
      let наблюдалось = черновик.наблюдалось ?? запрос.времяСоздания
      if запрос.времяСоздания.timeIntervalSince(наблюдалось)
        > запрос.пределУстареванияСекунд
      {
        черновик.статусы.insert(.устарел)
      }
      if черновик.свидетельства.isEmpty {
        черновик.добавитьСвидетельство(
          источник: .оценкаПокрытия, наблюдалось: запрос.времяСоздания,
          версия: запрос.версия, текущее: false)
      }
      let свидетельства = черновик.свидетельства
      let источники = черновик.источники.sorted { $0.rawValue < $1.rawValue }
      записи.append(ЗаписьСнимка(
        идентификатор: ожидаемый.идентификатор,
        репозиторий: черновик.линияИзвестна ? черновик.репозиторий : nil,
        корень: черновик.линияИзвестна ? черновик.корень : nil,
        родитель: черновик.линияИзвестна ? черновик.родитель : nil,
        предки: черновик.линияИзвестна ? черновик.предки : [],
        линияИзвестна: черновик.линияИзвестна,
        наблюдалось: наблюдалось,
        источники: источники,
        свидетельства: свидетельства,
        версия: запрос.версия,
        статусы: черновик.статусы.sorted { $0.rawValue < $1.rawValue },
        предыдущиеСтатусы: черновик.предыдущиеСтатусы.sorted { $0.rawValue < $1.rawValue }
      ))
      try прибавить(1, к: &счётчики.записейСнимка)
    }
    let естьПробелы = !недостающие.isEmpty || достигнутЛимитОбычногоСписка
      || пропущеноХостов > 0 || пропущеноИсточников > 0
      || неверныхИдентификаторов > 0 || строкВнеОбласти > 0
      || неверныхОпросов > 0
      || неадресныхОпросов > 0 || истеклоОжиданий > 0 || ошибокОжиданий > 0
      || пустыхСнимковОжидания > 0 || естьСбойИлиОграничениеЁмкости
      || естьУзлыСНеизвестнойЛинией
      || доступностьСписка != .доступно
      || доступностиОжиданий.contains(where: { $0 != .доступно })
    let полнота: СостояниеПокрытия = валидныхИсточников == 0
      ? .неизвестное : (естьПробелы ? .неполное : .ограниченное)

    var завершённыеСчётчики = счётчики
    try прибавить(счётчики.строкСписка, к: &завершённыеСчётчики.операций)
    try прибавить(счётчики.опросов, к: &завершённыеСчётчики.операций)
    try прибавить(счётчики.целейОжидания, к: &завершённыеСчётчики.операций)
    try прибавить(счётчики.ожидаемыхУзлов, к: &завершённыеСчётчики.операций)
    try прибавить(счётчики.связейЛинии, к: &завершённыеСчётчики.операций)
    try прибавить(счётчики.предыдущихЗаписей, к: &завершённыеСчётчики.операций)
    try прибавить(счётчики.эфемерныхАгентов, к: &завершённыеСчётчики.операций)
    try прибавить(счётчики.записейСнимка, к: &завершённыеСчётчики.операций)

    let покрытие = ПокрытиеСнимка(
      доступностьСписка: доступностьСписка,
      доступностиОжиданий: доступностиОжиданий,
      недостающиеОжидаемыеУзлы: недостающие,
      достигнутЛимитОбычногоСписка: достигнутЛимитОбычногоСписка,
      пропущеноИсточников: пропущеноИсточников,
      пропущеноХостов: пропущеноХостов,
      неверныхИдентификаторов: неверныхИдентификаторов,
      неверныхОпросов: неверныхОпросов,
      строкВнеОбласти: строкВнеОбласти,
      неадресныхОпросов: неадресныхОпросов,
      пустыхСнимковОжидания: пустыхСнимковОжидания,
      истеклоОжиданий: истеклоОжиданий,
      ошибокОжиданий: ошибокОжиданий,
      полнота: полнота
    )
    let счётчикиРезультата = СчётчикиНаблюдения(
      строкСпискаПрочитано: счётчики.строкСписка,
      опросовПрочитано: счётчики.опросов,
      целейОжиданияПрочитано: счётчики.целейОжидания,
      ожидаемыхУзловПрочитано: счётчики.ожидаемыхУзлов,
      связейЛинииПрочитано: счётчики.связейЛинии,
      предыдущихЗаписейПрочитано: счётчики.предыдущихЗаписей,
      эфемерныхАгентовПрочитано: счётчики.эфемерныхАгентов,
      записейСнимка: счётчики.записейСнимка,
      операций: завершённыеСчётчики.операций,
      доступныхБайтов: доступныеБайты
    )
    return СнимокНаблюдений(
      репозиторий: запрос.репозиторий, корень: запрос.корень,
      версия: запрос.версия, создано: запрос.времяСоздания,
      записи: записи, покрытие: покрытие, счётчики: счётчикиРезультата
    )
  }

  private static func корректен(_ узел: УзелНаблюдения) -> Bool {
    switch узел.вид {
    case .поток:
      guard let uuid = узел.uuid, let hostID = узел.hostID,
        !hostID.isEmpty, hostID.utf8.count <= 128,
        hostID == hostID.trimmingCharacters(in: .whitespacesAndNewlines)
      else { return false }
      return uuid.uuidString.lowercased() == узел.значение
    case .эфемерныйАгент:
      return узел.hostID == nil && !узел.значение.isEmpty
        && узел.значение.utf8.count <= 256
    }
  }

  private static func корректнаЛиния(
    идентификатор: УзелНаблюдения, репозиторий: String?, корень: UUID?,
    родитель: УзелНаблюдения?, предки: [УзелНаблюдения],
    репозиторийЗапроса: String, кореньЗапроса: UUID
  ) -> Bool {
    guard корректен(идентификатор), репозиторий == репозиторийЗапроса,
      корень == кореньЗапроса
    else { return false }
    var уникальныеПредки = Set<УзелНаблюдения>()
    for предок in предки {
      guard корректен(предок), уникальныеПредки.insert(предок).inserted else {
        return false
      }
      guard предок != идентификатор else { return false }
    }
    if идентификатор.uuid == кореньЗапроса {
      return родитель == nil && предки.isEmpty
    }
    guard let родитель, корректен(родитель), родитель != идентификатор,
      предки.last == родитель, предки.first?.uuid == кореньЗапроса
    else { return false }
    return true
  }

  private static func идентификаторПотока(_ строка: ЗаписьПотока) -> УзелНаблюдения? {
    guard let rawID = строка.id, let uuid = UUID(uuidString: rawID),
      let hostID = строка.hostID, !hostID.isEmpty,
      hostID.utf8.count <= 128,
      hostID == hostID.trimmingCharacters(in: .whitespacesAndNewlines)
    else { return nil }
    return .поток(uuid, hostID: hostID)
  }

  private static func подписьAPI(_ статус: СтатусПотока?) -> ПодписьСтатусаAPI? {
    guard let статус,
      статус.тип != nil || !статус.активныеФлаги.isEmpty
    else { return nil }
    return ПодписьСтатусаAPI(тип: статус.тип, активныеФлаги: Set(статус.активныеФлаги))
  }

  private static func добавитьСтатусAPI(
    _ статус: СтатусПотока?, в черновик: ЧерновикЗаписи
  ) {
    if let подпись = подписьAPI(статус) {
      черновик.состоянияAPI.insert(подпись)
    }
    if let тип = статус?.тип {
      добавитьСмысловойСтатус(тип, в: &черновик.статусы)
    }
    for флаг in статус?.активныеФлаги ?? [] {
      добавитьСмысловойСтатус(флаг, в: &черновик.статусы)
    }
  }

  private static func добавитьСмысловойСтатус(
    _ исходный: String, разрешитьВыполнение: Bool = false,
    в статусы: inout Set<СмысловойСтатус>
  ) {
    if исходный == "inProgress" {
      if разрешитьВыполнение { статусы.insert(.выполняется) }
      return
    }
    switch исходный {
    case "active": статусы.insert(.активенПоAPI)
    case "waitingForTool": статусы.insert(.ожиданиеИнструмента)
    case "waitingForChild": статусы.insert(.ожиданиеДочернегоУзла)
    case "waitingForHuman": статусы.insert(.ожиданиеЧеловека)
    case "readyHandoff": статусы.insert(.готовКПередаче)
    case "paused": статусы.insert(.приостановлен)
    case "cancelled": статусы.insert(.отменён)
    case "completed": статусы.insert(.завершён)
    case "failed": статусы.insert(.сбой)
    case "capacity", "capacityLimited", "rateLimited": статусы.insert(.ограниченЁмкостью)
    default: break
    }
  }

  private static func являетсяЁмкостнымОграничением(_ статус: String) -> Bool {
    статус == "capacity" || статус == "capacityLimited" || статус == "rateLimited"
  }

  private static func являетсяОпросомПотоков(_ имя: String?) -> Bool {
    имя == "wait_threads" || имя == "mcp__codex_app__wait_threads"
  }

  private static func эффективнаяДоступность(
    _ доступность: ДоступностьОтвета, байты: Int
  ) -> ДоступностьОтвета {
    if доступность == .доступно && байты > пределБайтовОдногоОтвета {
      return .превышенРазмер
    }
    return доступность
  }

  private static func обнаруженКонфликт(
    _ статусы: Set<СмысловойСтатус>, черновик: ЧерновикЗаписи
  ) -> Bool {
    if черновик.состоянияAPI.count > 1 || черновик.состоянияХода.count > 1
      || черновик.состоянияАгента.count > 1
    { return true }

    let завершённые = статусы.intersection([.приостановлен, .отменён, .завершён, .сбой, .ограниченЁмкостью])
    let ожидания = статусы.intersection([
      .ожиданиеЧеловека, .ожиданиеИнструмента, .ожиданиеДочернегоУзла, .готовКПередаче
    ])
    if завершённые.count > 1 { return true }
    if !завершённые.isEmpty && !ожидания.isEmpty { return true }
    if !завершённые.isEmpty
      && (статусы.contains(.выполняется) || статусы.contains(.содержательнаяРабота))
    { return true }
    if статусы.contains(.приостановлен)
      && (статусы.contains(.активенПоAPI) || статусы.contains(.ожиданиеДочернегоУзла)
        || статусы.contains(.выполняется) || статусы.contains(.содержательнаяРабота))
    { return true }
    return false
  }

  private static func учестьБайты(_ число: Int, в итого: inout Int) throws {
    guard число >= 0 else { throw ОшибкаСнимка.неверныеПределы }
    try прибавить(число, к: &итого)
    guard итого <= пределБайтовСнимка else { throw ОшибкаСнимка.превышенПределБайтов }
  }

  private static func прибавить(_ число: Int, к счётчик: inout Int) throws {
    guard число >= 0 else { throw ОшибкаСнимка.неверныеПределы }
    let (результат, переполнение) = счётчик.addingReportingOverflow(число)
    guard !переполнение else { throw ОшибкаСнимка.переполнениеСчётчика }
    счётчик = результат
  }

  private static func учестьСвязи(
    _ число: Int, для запрос: ЗапросСнимка, в счётчики: inout ЧерновикСчётчиков
  ) throws {
    try прибавить(число, к: &счётчики.связейЛинии)
    guard счётчики.связейЛинии <= запрос.пределЗаписей else {
      throw ОшибкаСнимка.превышенПределЗаписей
    }
  }

  private struct КлючСвидетельства: Hashable {
    let источник: ИсточникЗаписи
    let наблюдалось: Date
    let версия: Int
  }

  private struct ПодписьСтатусаAPI: Hashable {
    let тип: String?
    let активныеФлаги: Set<String>
  }

  private final class ЧерновикЗаписи {
    let идентификатор: УзелНаблюдения
    var репозиторий: String?
    var корень: UUID?
    var родитель: УзелНаблюдения?
    var предки: [УзелНаблюдения]
    var линияИзвестна: Bool
    var статусы: Set<СмысловойСтатус> = []
    var предыдущиеСтатусы: Set<СмысловойСтатус> = []
    var источники: Set<ИсточникЗаписи> = []
    var ключиСвидетельств: Set<КлючСвидетельства> = []
    var свидетельства: [СвидетельствоЗаписи] = []
    var состоянияAPI: Set<ПодписьСтатусаAPI> = []
    var состоянияХода: Set<String> = []
    var состоянияАгента: Set<String> = []
    var текущихНаблюдений = 0
    var наблюдалось: Date?

    init(ожидаемый: ОжидаемыйУзел) {
      идентификатор = ожидаемый.идентификатор
      if ожидаемый.линияИзвестна {
        репозиторий = ожидаемый.репозиторий
        корень = ожидаемый.корень
        родитель = ожидаемый.родитель
        предки = ожидаемый.предки
        линияИзвестна = true
      } else {
        репозиторий = nil
        корень = nil
        родитель = nil
        предки = []
        линияИзвестна = false
      }
    }

    func добавитьСвидетельство(
      источник: ИсточникЗаписи, наблюдалось: Date, версия: Int, текущее: Bool
    ) {
      let ключ = КлючСвидетельства(источник: источник, наблюдалось: наблюдалось, версия: версия)
      if ключиСвидетельств.insert(ключ).inserted {
        свидетельства.append(СвидетельствоЗаписи(
          источник: источник, наблюдалось: наблюдалось, версия: версия))
      }
      источники.insert(источник)
      if текущее { текущихНаблюдений += 1 }
      if let предыдущийМомент = self.наблюдалось {
        if предыдущийМомент < наблюдалось { self.наблюдалось = наблюдалось }
      } else {
        self.наблюдалось = наблюдалось
      }
    }
  }

  private struct ЧерновикСчётчиков {
    var строкСписка = 0
    var опросов = 0
    var целейОжидания = 0
    var ожидаемыхУзлов = 0
    var связейЛинии = 0
    var предыдущихЗаписей = 0
    var эфемерныхАгентов = 0
    var записейСнимка = 0
    var операций = 0
  }

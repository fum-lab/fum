import Foundation
import CryptoKit

public struct ОсноваПопытки: Codable, Equatable, Sendable {
    public let адрес: АдресУзла
    public let исполнитель: ЭкземплярУзла
    public let действие: ВидДействияФабрики
    public let хэшВхода: String
    public let ожидаемыйХэшРезультата: String?
}

public enum ИдентификаторПопытки {
    public static func построить(_ основа: ОсноваПопытки) throws -> НамерениеПопытки {
        guard корректныйSHA256(основа.хэшВхода),
              основа.ожидаемыйХэшРезультата.map(корректныйSHA256) ?? true else { throw ОшибкаПопытки.неверныйХэш }
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        let каноническая = ОсноваПопытки(адрес: основа.адрес.канонический(), исполнитель: основа.исполнитель.канонический(),
            действие: основа.действие, хэшВхода: основа.хэшВхода, ожидаемыйХэшРезультата: основа.ожидаемыйХэшРезультата)
        let данные = try кодировщик.encode(каноническая)
        let идентификатор = SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
        return НамерениеПопытки(идентификатор: идентификатор, хэшВхода: основа.хэшВхода, ожидаемыйХэшРезультата: основа.ожидаемыйХэшРезультата, основа: каноническая)
    }
}

public enum ОшибкаПопытки: Error { case неверныйХэш }

public struct НамерениеПопытки: Codable, Equatable, Sendable {
    public let идентификатор: String
    public let хэшВхода: String
    public let ожидаемыйХэшРезультата: String?
    public let основа: ОсноваПопытки?

    public init(идентификатор: String, хэшВхода: String, ожидаемыйХэшРезультата: String? = nil, основа: ОсноваПопытки? = nil) {
        self.идентификатор = идентификатор
        self.хэшВхода = хэшВхода
        self.ожидаемыйХэшРезультата = ожидаемыйХэшРезультата
        self.основа = основа
    }
}

public enum ИсходПопытки: String, Codable, Equatable, Sendable {
    case подтверждён, отказ, неизвестен
}

public enum РешениеПовтора: Equatable, Sendable {
    case создатьНамерение, вернутьИсход, неизвестно, конфликт

    public static func определить(новое: НамерениеПопытки, сохранённое: НамерениеПопытки?, исход: ИсходПопытки?) -> Self {
        guard !новое.идентификатор.isEmpty, !новое.хэшВхода.isEmpty else { return .конфликт }
        guard let сохранённое else { return исход == nil ? .создатьНамерение : .конфликт }
        guard сохранённое == новое else { return .конфликт }
        guard let исход else { return .неизвестно }
        return исход == .неизвестен ? .неизвестно : .вернутьИсход
    }
}

public protocol ХранилищеПопыток: Sendable {
    /// Адаптер обязан обеспечивать атомарное создание и целостность ВСЕГО состояния:
    /// исход и сверка проверяют наличие и неизменность намерения и друг друга в одной
    /// транзакции. Долговечность и подлинность утверждения адаптера ядро не доказывает.
    func поддерживаетДолговечнуюЗапись() async -> Bool
    func установитьНамерение(_ намерение: НамерениеПопытки) async throws -> ИтогУстановкиНамерения
    func установитьИсход(_ исход: ИсходПопытки, для намерения: НамерениеПопытки) async throws -> ИтогУстановкиИсхода
    func установитьСверку(_ сверка: СвидетельствоСверки, для намерения: НамерениеПопытки) async throws -> ИтогУстановкиИсхода
    func сверка(идентификатор: String) async throws -> СвидетельствоСверки?
    func намерение(идентификатор: String) async throws -> НамерениеПопытки?
    func исход(идентификатор: String) async throws -> ИсходПопытки?
}

public struct СвидетельствоСверки: Codable, Equatable, Sendable {
    public let ожидаемыйХэш: String
    public let наблюдённыйХэш: String
}

private func корректныйSHA256(_ значение: String) -> Bool {
    значение.utf8.count == 64 && значение.utf8.allSatisfy {
        (48...57).contains($0) || (97...102).contains($0)
    }
}

public enum ИтогУстановкиНамерения: Equatable, Sendable { case создано, существует, конфликт }
public enum ИтогУстановкиИсхода: Equatable, Sendable { case создано, существует, конфликт }

public enum ПодготовкаПопытки: Equatable, Sendable {
    case требуетсяПовторнаяСверкаВладения, сохранённыйИсход(ИсходПопытки), неизвестно, конфликт
    case отказДопуска(РешениеДопуска)
}

public enum СверкаПопытки: Equatable, Sendable {
    case записьИсходаЗаявлена(ИсходПопытки), совпадениеЗаявленныхХэшей, неизвестно, конфликт
}

/// Только протокол и проверяемая последовательность. Исполнитель среды не вызывается.
public enum КоординаторПопытки {
    // Подтверждающий адаптер пока отсутствует: никакая caller-supplied отметка его не заменяет.
    private static let доверенныйИсточникДоступен = false
    private static func связано(_ попытка: НамерениеПопытки, владение: ЛокальноеВладение, токен: UUID) async -> Bool {
        guard let основа = попытка.основа,
              let проверенная = try? ИдентификаторПопытки.построить(основа), проверенная == попытка else { return false }
        let назначение = владение.назначение
        return await владение.соответствует(адрес: основа.адрес, исполнитель: основа.исполнитель,
                                             назначение: назначение, токен: токен)
    }
    public static func сверитьНеизвестныйИсход(
        _ попытка: НамерениеПопытки,
        хранилище: any ХранилищеПопыток
    ) async -> СверкаПопытки {
        guard await хранилище.поддерживаетДолговечнуюЗапись() else { return .неизвестно }
        do {
            guard let сохранённое = try await хранилище.намерение(идентификатор: попытка.идентификатор) else {
                return .неизвестно
            }
            guard сохранённое == попытка else { return .конфликт }
            if let исход = try await хранилище.исход(идентификатор: попытка.идентификатор), исход != .неизвестен {
                return .записьИсходаЗаявлена(исход)
            }
            guard let сверка = try await хранилище.сверка(идентификатор: попытка.идентификатор) else { return .неизвестно }
            guard корректныйSHA256(сверка.ожидаемыйХэш), сверка.ожидаемыйХэш == сверка.наблюдённыйХэш,
                  сверка.ожидаемыйХэш == попытка.ожидаемыйХэшРезультата else { return .конфликт }
            return .совпадениеЗаявленныхХэшей
        } catch {
            return .неизвестно
        }
    }

    /// Принимает только отдельное точное readback-свидетельство, не удаляя старый UNKNOWN.
    public static func сохранитьСверку(
        _ сверка: СвидетельствоСверки,
        попытка: НамерениеПопытки,
        хранилище: any ХранилищеПопыток,
        владение: ЛокальноеВладение,
        токен: UUID
    ) async -> СверкаПопытки {
        guard доверенныйИсточникДоступен else { return .неизвестно }
        guard await хранилище.поддерживаетДолговечнуюЗапись() else { return .неизвестно }
        guard await связано(попытка, владение: владение, токен: токен) else { return .неизвестно }
        guard корректныйSHA256(сверка.ожидаемыйХэш), сверка.ожидаемыйХэш == сверка.наблюдённыйХэш else { return .конфликт }
        return await владение.сВладением(токен: токен) { () async -> СверкаПопытки in
        do {
            guard try await хранилище.намерение(идентификатор: попытка.идентификатор) == попытка else { return .конфликт }
            guard сверка.ожидаемыйХэш == попытка.ожидаемыйХэшРезультата else { return .конфликт }
            let прежнийИсход = try await хранилище.исход(идентификатор: попытка.идентификатор)
            guard прежнийИсход == nil || прежнийИсход == .неизвестен else { return .конфликт }
            let установка = try await хранилище.установитьСверку(сверка, для: попытка)
            guard установка != .конфликт else { return .конфликт }
            guard try await хранилище.сверка(идентификатор: попытка.идентификатор) == сверка else { return .неизвестно }
            return .совпадениеЗаявленныхХэшей
        } catch { return .неизвестно }
        } ?? .неизвестно
    }

    public static func подготовить(
        _ попытка: НамерениеПопытки,
        вход: ВходДопускаФабрики,
        действие: ВидДействияФабрики,
        хранилище: any ХранилищеПопыток,
        владение: ЛокальноеВладение,
        токен: UUID
    ) async -> ПодготовкаПопытки {
        guard await хранилище.поддерживаетДолговечнуюЗапись() else { return .неизвестно }
        guard await владение.соответствует(адрес: вход.адрес, исполнитель: вход.исполнитель,
            назначение: вход.назначениеПространства, токен: токен) else { return .неизвестно }
        let допуск = ПроверкаПередЗапуском.проверить(вход, действие: действие)
        guard допуск == .условноДопустимо else { return .отказДопуска(допуск) }
        guard !попытка.идентификатор.isEmpty, !попытка.хэшВхода.isEmpty else { return .конфликт }
        let основа = ОсноваПопытки(адрес: вход.адрес, исполнитель: вход.исполнитель,
            действие: действие, хэшВхода: попытка.хэшВхода,
            ожидаемыйХэшРезультата: попытка.ожидаемыйХэшРезультата)
        guard let провереннаяПопытка = try? ИдентификаторПопытки.построить(основа),
              провереннаяПопытка == попытка else { return .конфликт }
        return await владение.сВладением(токен: токен) { () async -> ПодготовкаПопытки in
        do {
            let установка = try await хранилище.установитьНамерение(попытка)
            guard установка != .конфликт else { return .конфликт }
            guard try await хранилище.намерение(идентификатор: попытка.идентификатор) == попытка else {
                return .неизвестно
            }
            let исход = try await хранилище.исход(идентификатор: попытка.идентификатор)
            if let исход {
                if исход != .неизвестен { return .сохранённыйИсход(исход) }
                if установка == .создано { return .неизвестно }
            }
            if установка == .существует,
               let сверка = try await хранилище.сверка(идентификатор: попытка.идентификатор) {
                guard корректныйSHA256(сверка.ожидаемыйХэш),
                      сверка.ожидаемыйХэш == сверка.наблюдённыйХэш,
                      сверка.ожидаемыйХэш == попытка.ожидаемыйХэшРезультата else { return .конфликт }
                // Равенство представленных хэшей не подтверждает readback цели.
                return .неизвестно
            }
            return установка == .создано ? .требуетсяПовторнаяСверкаВладения : .неизвестно
        } catch {
            return .неизвестно
        }
        } ?? .неизвестно
    }

    public static func сохранитьИсход(
        _ исход: ИсходПопытки,
        попытка: НамерениеПопытки,
        хранилище: any ХранилищеПопыток,
        владение: ЛокальноеВладение,
        токен: UUID
    ) async -> СверкаПопытки {
        guard доверенныйИсточникДоступен else { return .неизвестно }
        guard await хранилище.поддерживаетДолговечнуюЗапись() else { return .неизвестно }
        guard await связано(попытка, владение: владение, токен: токен) else { return .неизвестно }
        return await владение.сВладением(токен: токен) { () async -> СверкаПопытки in
        do {
            guard try await хранилище.намерение(идентификатор: попытка.идентификатор) == попытка else {
                return .конфликт
            }
            let установка = try await хранилище.установитьИсход(исход, для: попытка)
            guard установка != .конфликт else { return .конфликт }
            guard try await хранилище.исход(идентификатор: попытка.идентификатор) == исход else {
                return .неизвестно
            }
            return исход == .неизвестен ? .неизвестно : .записьИсходаЗаявлена(исход)
        } catch {
            return .неизвестно
        }
        } ?? .неизвестно
    }
}

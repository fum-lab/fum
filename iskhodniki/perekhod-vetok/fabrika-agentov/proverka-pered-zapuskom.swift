import Foundation

public enum НаблюдениеВладельца: String, Codable, Sendable {
    case свой, занят, неизвестен
}

public enum СостояниеУправления: String, Codable, Sendable {
    case готов, пауза, отмена, d22, активен, неизвестно
}

public enum ПроисхождениеБазы: String, Codable, Sendable {
    case предок, неПредок, неизвестно
}

public enum ПамятьЭффектов: String, Codable, Sendable {
    case подтверждена, недоступна
}

public enum МежхостовоеВладение: String, Codable, Sendable {
    case подтверждено, неизвестно
}

public struct ВходДопускаФабрики: Codable, Sendable {
    public var адрес: АдресУзла
    public var исполнитель: ЭкземплярУзла
    public var ожидаемыйИсполнитель: ЭкземплярУзла
    public var ожидаемыйАдрес: АдресУзла
    public var владелец: НаблюдениеВладельца
    public var управление: СостояниеУправления
    public var происхождениеБазы: ПроисхождениеБазы
    public var снимокСовпадает: Bool
    public var памятьЭффектов: ПамятьЭффектов
    public var назначениеПространства: НазначениеПространства?
    public var межхостовоеВладение: МежхостовоеВладение
}

public enum РешениеДопуска: Equatable, Sendable {
    case условноДопустимо, толькоПлан, занято, неизвестно, несовпадение, неПредок, дрейф
    case управление(СостояниеУправления)
}

public enum ПроверкаПередЗапуском {
    public static func проверить(_ вход: ВходДопускаФабрики, действие: ВидДействияФабрики) -> РешениеДопуска {
        _ = действие
        guard вход.управление == .готов else { return .управление(вход.управление) }
        guard !вход.адрес.репозиторий.isEmpty, !вход.адрес.ветка.isEmpty,
              !вход.адрес.путьПамяти.isEmpty, !вход.исполнитель.хост.isEmpty,
              !вход.исполнитель.воплощение.isEmpty, !вход.исполнитель.задача.isEmpty,
              !вход.исполнитель.родитель.isEmpty, !вход.исполнитель.модель.isEmpty,
              !вход.исполнитель.усилие.isEmpty, !вход.исполнитель.рабочееДерево.isEmpty,
              (вход.исполнитель.идентификаторПамяти == nil) == (вход.исполнитель.кореньПамяти == nil)
        else { return .несовпадение }
        guard вход.адрес == вход.ожидаемыйАдрес,
              вход.исполнитель == вход.ожидаемыйИсполнитель else { return .несовпадение }
        switch вход.владелец {
        case .занят: return .занято
        case .неизвестен: return .неизвестно
        case .свой: break
        }
        switch вход.происхождениеБазы {
        case .неПредок: return .неПредок
        case .неизвестно: return .неизвестно
        case .предок: break
        }
        guard вход.снимокСовпадает else { return .дрейф }
        guard let назначение = вход.назначениеПространства else { return .толькоПлан }
        guard назначение.адрес == вход.адрес, назначение.хост == вход.исполнитель.хост,
              назначение.физическийКорень.hasPrefix("/"), назначение.inode != 0 else { return .несовпадение }
        guard вход.межхостовоеВладение == .подтверждено else { return .толькоПлан }
        // Caller-supplied факты не подтверждают назначение, межхостовое владение или storage.
        // До подключения независимого проверенного источника разрешения нет.
        return .толькоПлан
    }
}

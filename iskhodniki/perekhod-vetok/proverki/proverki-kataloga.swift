        игнорируемыеФайлы: игнорируемыеФайлы)
}

private func построитьПланКаталога(
    запрос: ЗапросВосстановленияКаталога = запросКаталога(),
    сеансы: [НаблюдениеСеансаКаталога] = [наблюдениеСеансаКаталога()],
    наблюдения: [НаблюдениеРепозиторияКаталога] = [наблюдениеGitКаталога()],
    контекст: КонтекстНаблюденийКаталога = .доверенныйТестовый
) throws -> ПланКаталогаВосстановления {
    try ПланировщикКаталогаВосстановления.построить(
        запрос, сеансы: сеансы, наблюденияРепозитория: наблюдения, контекст: контекст)
}


import Testing
@testable import МатериализацияУзлов

func обычнаяРабота() -> УсловияСамостоятельности {
    УсловияСамостоятельности(свояОбласть: true, естьПолномочия: true,
        неизвестныйОпасныйЭффект: false, естьПолезноеПродвижение: true,
        можноБезопасноПродолжать: true, доступнаНезависимаяРабота: false,
        локальнаяИсправимаяПроблема: false)
}

@Suite struct ПроверкиСамостоятельности {
    @Test func разрешённаяРаботаНеЖдётРазрешения() throws {
        #expect(try СамостоятельностьУзла.решить(обычнаяРабота()) ==
            РешениеСамостоятельности(действие: .действоватьСамостоятельно, основание: nil))
    }

    @Test func локальнаяПроблемаИсправляетсяСамостоятельно() throws {
        var условия = обычнаяРабота()
        условия.локальнаяИсправимаяПроблема = true
        #expect(try СамостоятельностьУзла.решить(условия) ==
            РешениеСамостоятельности(действие: .исправлятьСамостоятельно, основание: nil))
    }

    @Test(arguments: ОснованиеОбращения.allCases)
    func границыНеОткрываютсяЛокальнойПроблемой(_ основание: ОснованиеОбращения) throws {
        var условия = обычнаяРабота()
        условия.локальнаяИсправимаяПроблема = true
        switch основание {
        case .неизвестныйОпасныйЭффект: условия.неизвестныйОпасныйЭффект = true
        case .чужаяОбласть: условия.свояОбласть = false
        case .нужныПолномочия: условия.естьПолномочия = false
        case .безопасноеПродолжениеНевозможно: условия.можноБезопасноПродолжать = false
        case .нетПолезногоПродвижения: условия.естьПолезноеПродвижение = false
        }
        #expect(try СамостоятельностьУзла.решить(условия) ==
            РешениеСамостоятельности(действие: .сообщитьРодителю, основание: основание))
    }

    @Test func независимаяРаботаПродолжаетсяПриЭскалации() throws {
        var условия = обычнаяРабота()
        условия.неизвестныйОпасныйЭффект = true
        условия.доступнаНезависимаяРабота = true
        #expect(try СамостоятельностьУзла.решить(условия) ==
            РешениеСамостоятельности(действие: .сообщитьИПродолжитьНезависимое,
                                    основание: .неизвестныйОпасныйЭффект))
    }

    @Test func опасныйЭффектНеТеряетсяПриДругомПрепятствии() throws {
        var условия = обычнаяРабота()
        условия.свояОбласть = false
        условия.неизвестныйОпасныйЭффект = true
        #expect(try СамостоятельностьУзла.решить(условия).основание == .неизвестныйОпасныйЭффект)
    }
}

public struct УсловияСамостоятельности: Codable, Sendable {
    public var свояОбласть: Bool
    public var естьПолномочия: Bool
    public var неизвестныйОпасныйЭффект: Bool
    public var естьНакопленноеПродвижение: Bool
    public var можноБезопасноПродолжать: Bool
    public var доступнаНезависимаяРабота: Bool
    public var локальнаяИсправимаяПроблема: Bool
    public var остановкаЗадачи: Bool
    public var естьБезопасныйСледующийШаг: Bool

    public init(свояОбласть: Bool, естьПолномочия: Bool, неизвестныйОпасныйЭффект: Bool,
                естьНакопленноеПродвижение: Bool, можноБезопасноПродолжать: Bool,
                доступнаНезависимаяРабота: Bool, локальнаяИсправимаяПроблема: Bool,
                остановкаЗадачи: Bool, естьБезопасныйСледующийШаг: Bool) {
        self.свояОбласть = свояОбласть
        self.естьПолномочия = естьПолномочия
        self.неизвестныйОпасныйЭффект = неизвестныйОпасныйЭффект
        self.естьНакопленноеПродвижение = естьНакопленноеПродвижение
        self.можноБезопасноПродолжать = можноБезопасноПродолжать
        self.доступнаНезависимаяРабота = доступнаНезависимаяРабота
        self.локальнаяИсправимаяПроблема = локальнаяИсправимаяПроблема
        self.остановкаЗадачи = остановкаЗадачи
        self.естьБезопасныйСледующийШаг = естьБезопасныйСледующийШаг
    }
}

public enum ДействиеУзла: String, Codable, Sendable {
    case действоватьСамостоятельно, исправлятьСамостоятельно
    case сообщитьРодителю, сообщитьИПродолжитьНезависимое
    case остановиться
}

public enum ОснованиеОбращения: String, Codable, Sendable, CaseIterable {
    case неизвестныйОпасныйЭффект, чужаяОбласть, нужныПолномочия
    case безопасноеПродолжениеНевозможно, нетБезопасногоСледующегоШага
}

public struct РешениеСамостоятельности: Codable, Sendable, Equatable {
    public let действие: ДействиеУзла
    public let основание: ОснованиеОбращения?
}

public enum СамостоятельностьУзла {
    public static func решить(_ условия: УсловияСамостоятельности) throws -> РешениеСамостоятельности {
        guard let путь = Bundle.module.url(forResource: "samostoyateljnostj", withExtension: "json",
                                            subdirectory: "opredeleniya")
        else { throw ОтказСамостоятельности.определение }
        let определение = try ОпределениеОператора.разобрать(Data(contentsOf: путь))
        guard определение.идентификатор == "fum.решить-самостоятельность-узла",
              определение.шаги.count == 1,
              case .вычислитьJSON = определение.шаги[0].действие
        else { throw ОтказСамостоятельности.определение }
        let вход = String(decoding: try JSONEncoder().encode(условия), as: UTF8.self)
        let исполнение = try AutomationExecutor.выполнить(определение, вход: .текст(вход))
        guard case .текст(let результат) = исполнение.результат
        else { throw ОтказСамостоятельности.результат }
        return try JSONDecoder().decode(РешениеСамостоятельности.self, from: Data(результат.utf8))
    }
}

public enum ОтказСамостоятельности: Error, Sendable { case определение, результат }

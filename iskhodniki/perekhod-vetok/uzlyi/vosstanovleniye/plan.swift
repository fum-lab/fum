public enum ВосстановлениеУзлов {
    public static func построить(
        _ спецификация: СпецификацияВосстановления,
        наблюдение: НаблюдениеВосстановления
    ) throws -> ПланВосстановления {
        try проверить(спецификация, наблюдение: наблюдение)
        let факты = ФактыFUMA(
            остановка: спецификация.ребёнок.желаемоеСостояние == .остановлено,
            пауза: спецификация.ребёнок.желаемоеСостояние == .приостановлено,
            противоречивыйУспехЭффекта:
                наблюдение.создание == .подтверждёнУспех
                    && наблюдение.экземпляр == .отсутствует
                || наблюдение.отправка == .подтверждёнУспех
                    && наблюдение.долговечноеСообщение != nil
                    && !наблюдение.сообщениеУжеДоставлено,
            неизвестныйЭффект: наблюдение.создание == .неизвестен
                || наблюдение.отправка == .неизвестен || наблюдение.git == .неизвестен,
            неполныйСписок: !наблюдение.списокПолон,
            неизвестныйМаршрутИлиВладелец: !наблюдение.маршрутПодтверждён
                || !наблюдение.владелецПодтверждён,
            чужойПисатель: наблюдение.рабочаяОбласть == .чужойПисатель,
            новоеСообщение: наблюдение.долговечноеСообщение != nil
                && !наблюдение.сообщениеУжеДоставлено,
            родитель: наблюдение.родитель.rawValue,
            можноBootstrap: наблюдение.ближайшийЖивойПредок != nil
                && наблюдение.полномочияПредкаПодтверждены,
            текущийКаталогНеСовпадает: !наблюдение.текущийКаталогСовпадает,
            рабочаяОбласть: наблюдение.рабочаяОбласть.rawValue,
            веткаПодтверждена: наблюдение.веткаПодтверждена,
            экземпляр: наблюдение.экземпляр.rawValue,
            работа: наблюдение.работа.rawValue)
        let решение = try выполнитьFUMA(факты)
        let основание = основание(решение.действие, наблюдение: наблюдение)
        let рабочийКаталог = решение.действие == .использоватьСохранённуюРабочуюОбласть
            ? наблюдение.сохранённыйРабочийКаталог : nil
        let цель = цельЭффекта(
            решение.действие, спецификация: спецификация, наблюдение: наблюдение)
        let вид = видЭффекта(решение.действие)
        let идентификатор = try стабильныйХэш(
            ОсноваИдентификатораПлана(
                спецификация: спецификация, наблюдение: наблюдение,
                действие: решение.действие))
        let эффект = try вид.map { вид in
            ПланируемыйЭффект(
                идентификатор: try стабильныйХэш(
                    ОсноваИдентификатораЭффекта(
                        поручение: спецификация.ребёнок.идентификаторПоручения,
                        вид: вид, цель: цель,
                        сообщение: наблюдение.долговечноеСообщение)),
                вид: вид, цель: цель)
        }
        return ПланВосстановления(
            идентификатор: идентификатор, действие: решение.действие,
            основание: основание, рабочийКаталог: рабочийКаталог, эффект: эффект)
    }

    private static func проверить(
        _ спецификация: СпецификацияВосстановления,
        наблюдение: НаблюдениеВосстановления
    ) throws {
        let ребёнок = спецификация.ребёнок
        guard !спецификация.выполняющийУзел.isEmpty,
              !ребёнок.логическийИдентификатор.isEmpty,
              ребёнок.роль == .исполнительВосстановления,
              !ребёнок.ветка.isEmpty,
              ребёнок.программаПроверок.источник == .непосредственныйРодитель,
              !ребёнок.программаПроверок.проверки.isEmpty,
              Set(ребёнок.программаПроверок.проверки).count
                  == ребёнок.программаПроверок.проверки.count,
              !ребёнок.идентификаторПоручения.isEmpty else {
            throw ОшибкаВосстановления.неверныйВход
        }
        guard ребёнок.непосредственныйРодитель == спецификация.выполняющийУзел else {
            throw ОшибкаВосстановления.неНепосредственныйРебёнок
        }
        if наблюдение.экземпляр == .свой && наблюдение.uuid == nil {
            throw ОшибкаВосстановления.неверныйВход
        }
        if наблюдение.рабочаяОбласть == .своя
            && наблюдение.сохранённыйРабочийКаталог == nil {
            throw ОшибкаВосстановления.неверныйВход
        }
    }

    private static func выполнитьFUMA(_ факты: ФактыFUMA) throws -> РешениеFUMA {
        let определение = try ОпределениеОператора.разобрать(операторВосстановления)
        guard определение.идентификатор == "fum.спланировать-восстановление-узла",
              определение.шаги.count == 1,
              case .вычислитьJSON = определение.шаги[0].действие else {
            throw ОшибкаВосстановления.определениеFUMA
        }
        let вход = String(decoding: try кодировщик().encode(факты), as: UTF8.self)
        let исполнение = try AutomationExecutor.выполнить(определение, вход: .текст(вход))
        guard case .текст(let результат) = исполнение.результат else {
            throw ОшибкаВосстановления.результатFUMA
        }
        return try JSONDecoder().decode(РешениеFUMA.self, from: Data(результат.utf8))
    }

    private static func основание(
        _ действие: ДействиеВосстановления,
        наблюдение: НаблюдениеВосстановления
    ) -> ОснованиеВосстановления {
        switch действие {
        case .остановиться: .остановка
        case .сохранитьПаузу: .пауза
        case .сверитьПротиворечивыйЭффект: .противоречивыйЭффект
        case .сверитьНеизвестныйЭффект: .неизвестныйЭффект
        case .сверитьСписок: .неполныйСписок
        case .сверитьМаршрутИВладельца: .неизвестныйМаршрутИлиВладелец
        case .отказатьсяОтЗаписи: .чужойПисатель
        case .сверитьРодителя: .неизвестныйРодитель
        case .вернутьВниманиеРодителю, .возобновитьРодителя, .направитьBootstrapПредку:
            .долговечноеСообщение
        case .использоватьСохранённуюРабочуюОбласть: .сохранённаяРабочаяОбласть
        case .сверитьРабочуюОбласть: .неизвестнаяРабочаяОбласть
        case .подготовитьРабочуюОбластьИзВетки: .подтверждённаяВетка
        case .сверитьЭкземпляр: .неизвестныйЭкземпляр
        case .подготовитьСоздание: .подтверждённоеОтсутствие
        case .оставитьАктивным: .активнаяРабота
        case .возобновитьСуществующийУзел: .прерваннаяРабота
        case .ожидатьМощность: .отказМощности
        case .продолжитьСуществующееПоручение:
            наблюдение.работа == .локальныйИсправимыйСбой
                ? .локальныйИсправимыйСбой : .доставленныйНезавершённыйКоммит
        case .зафиксироватьЗавершение: .завершение
        case .зафиксироватьПриёмку: .приёмка
        }
    }

    private static func видЭффекта(_ действие: ДействиеВосстановления) -> ВидПланируемогоЭффекта? {
        switch действие {
        case .сверитьПротиворечивыйЭффект, .сверитьНеизвестныйЭффект,
             .сверитьСписок, .сверитьМаршрутИВладельца, .сверитьРодителя,
             .сверитьРабочуюОбласть, .сверитьЭкземпляр:
            .сверить
        case .подготовитьСоздание: .создать
        case .вернутьВниманиеРодителю: .отправить
        case .возобновитьРодителя, .возобновитьСуществующийУзел,
             .продолжитьСуществующееПоручение: .возобновить
        case .направитьBootstrapПредку: .bootstrap
        case .подготовитьРабочуюОбластьИзВетки: .подготовитьРабочуюОбласть
        case .остановиться, .сохранитьПаузу, .отказатьсяОтЗаписи,
             .использоватьСохранённуюРабочуюОбласть, .оставитьАктивным,
             .ожидатьМощность, .зафиксироватьЗавершение, .зафиксироватьПриёмку:
            nil
        }
    }

    private static func цельЭффекта(
        _ действие: ДействиеВосстановления,
        спецификация: СпецификацияВосстановления,
        наблюдение: НаблюдениеВосстановления
    ) -> String? {
        switch действие {
        case .подготовитьРабочуюОбластьИзВетки:
            спецификация.ребёнок.ветка
        case .вернутьВниманиеРодителю, .возобновитьРодителя:
            спецификация.выполняющийУзел
        case .направитьBootstrapПредку:
            наблюдение.ближайшийЖивойПредок

public enum ИсторияМоделиУзла {
    public static func спланироватьДобавление(
        _ история: [ЗаписьИсторииМодели],
        запись: ЗаписьИсторииМодели,
        область: ОбластьИсторииМодели
    ) throws -> ПланДобавленияИсторииМодели {
        let провереннаяИстория = try проверитьИсторию(история, область: область)
        try проверить(запись)
        guard запись.узел == область.узел,
              провереннаяИстория.порядокВеток[запись.ветка] != nil else {
            throw ОшибкаИсторииМодели.невернаяЗапись
        }
        let совпадение = провереннаяИстория.поИдентификатору[запись.идентификаторЗаписи]
        let состояние: СостояниеДобавленияИстории
        if let совпадение {
            состояние = совпадение == запись ? .точныйПовтор : .конфликт
        } else {
            guard запись.ветка == область.текущаяВетка else {
                throw ОшибкаИсторииМодели.невернаяЗапись
            }
            switch запись.вид {
            case .решение:
                guard !провереннаяИстория.решения.contains(запись.идентификаторРешения) else {
                    throw ОшибкаИсторииМодели.невернаяЗапись
                }
            case .ответAPI, .наблюдение, .поправка:
                guard провереннаяИстория.решения.contains(запись.идентификаторРешения) else {
                    throw ОшибкаИсторииМодели.невернаяЗапись
                }
            }
            состояние = .новое
        }
        let определение = try ОпределениеОператора.разобрать(операторИстории)
        guard определение.идентификатор == "fum.спланировать-добавление-истории-модели",
              определение.шаги.count == 1,
              case .вычислитьJSON = определение.шаги[0].действие else {
            throw ОшибкаИсторииМодели.определениеFUMA
        }
        let вход = String(decoding: try кодировщик().encode(ВходИсторииFUMA(состояние: состояние)), as: UTF8.self)
        let исполнение = try AutomationExecutor.выполнить(определение, вход: .текст(вход))
        guard case .текст(let результат) = исполнение.результат else {
            throw ОшибкаИсторииМодели.определениеFUMA
        }
        let решение = try JSONDecoder().decode(РешениеИсторииFUMA.self, from: Data(результат.utf8))
        return ПланДобавленияИсторииМодели(действие: решение.действие, запись: запись)
    }

    public static func применить(
        _ план: ПланДобавленияИсторииМодели,
        к история: [ЗаписьИсторииМодели],
        область: ОбластьИсторииМодели
    ) throws -> [ЗаписьИсторииМодели] {
        let ожидаемый = try спланироватьДобавление(
            история, запись: план.запись, область: область)
        guard ожидаемый == план else { throw ОшибкаИсторииМодели.несогласованныйПлан }
        switch план.действие {
        case .добавить:
            return история + [план.запись]
        case .неДобавлятьПовтор:
            return история
        case .отказатьКонфликт:
            throw ОшибкаИсторииМодели.конфликтИдентификатора
        }
    }

    public static func текущийПрофиль(
        _ история: [ЗаписьИсторииМодели],
        область: ОбластьИсторииМодели
    ) throws -> ПрофильМодели? {
        let провереннаяИстория = try проверитьИсторию(история, область: область)
        return провереннаяИстория.записи.last(where: {
            $0.вид == .наблюдение && $0.наблюдённыйПрофиль != nil
        })?
            .наблюдённыйПрофиль
    }

    private struct ПровереннаяИстория {
        let записи: [ЗаписьИсторииМодели]
        let поИдентификатору: [String: ЗаписьИсторииМодели]
        let решения: Set<String>
        let порядокВеток: [String: Int]
    }

    private static func проверитьИсторию(
        _ история: [ЗаписьИсторииМодели],
        область: ОбластьИсторииМодели
    ) throws -> ПровереннаяИстория {
        let порядокВеток = try порядокВеток(область)
        var записи: [ЗаписьИсторииМодели] = []
        var поИдентификатору: [String: ЗаписьИсторииМодели] = [:]
        var последнийНомерВетки: Int?
        for запись in история {
            try проверить(запись)
            guard запись.узел == область.узел,
                  let номерВетки = порядокВеток[запись.ветка] else {
                throw ОшибкаИсторииМодели.невернаяЗапись
            }
            if let прежняя = поИдентификатору[запись.идентификаторЗаписи] {
                guard прежняя == запись else {
                    throw ОшибкаИсторииМодели.конфликтИдентификатора
                }
            } else {
                guard последнийНомерВетки.map({ номерВетки >= $0 }) ?? true else {
                    throw ОшибкаИсторииМодели.невернаяЗапись
                }
                поИдентификатору[запись.идентификаторЗаписи] = запись
                записи.append(запись)
                последнийНомерВетки = номерВетки
            }
        }

        var решения: Set<String> = []
        for запись in записи {
            switch запись.вид {
            case .решение:
                guard решения.insert(запись.идентификаторРешения).inserted else {
                    throw ОшибкаИсторииМодели.невернаяЗапись
                }
            case .ответAPI, .наблюдение, .поправка:
                guard решения.contains(запись.идентификаторРешения) else {
                    throw ОшибкаИсторииМодели.невернаяЗапись
                }
            }
        }
        return ПровереннаяИстория(
            записи: записи,
            поИдентификатору: поИдентификатору,
            решения: решения,
            порядокВеток: порядокВеток)
    }

    private static func порядокВеток(
        _ область: ОбластьИсторииМодели
    ) throws -> [String: Int] {
        guard точнаяНепустаяСтрока(область.узел),
              точнаяНепустаяСтрока(область.текущаяВетка) else {
            throw ОшибкаИсторииМодели.невернаяЗапись
        }
        var поНазначению: [String: МиграцияВеткиИсторииМодели] = [:]
        for миграция in область.миграцииВетки {
            guard точнаяНепустаяСтрока(миграция.из),
                  точнаяНепустаяСтрока(миграция.в),
                  точнаяНепустаяСтрока(миграция.основание),
                  миграция.из != миграция.в,
                  поНазначению[миграция.в] == nil else {
                throw ОшибкаИсторииМодели.невернаяЗапись
            }
            поНазначению[миграция.в] = миграция
        }

        var обратнаяЦепочка = [область.текущаяВетка]
        var принятые: Set<String> = [область.текущаяВетка]
        var использованныеНазначения: Set<String> = []
        var текущая = область.текущаяВетка
        while let миграция = поНазначению[текущая] {
            guard принятые.insert(миграция.из).inserted else {
                throw ОшибкаИсторииМодели.невернаяЗапись
            }
            использованныеНазначения.insert(миграция.в)
            текущая = миграция.из
            обратнаяЦепочка.append(текущая)
        }
        guard использованныеНазначения.count == область.миграцииВетки.count else {
            throw ОшибкаИсторииМодели.невернаяЗапись
        }
        return Dictionary(uniqueKeysWithValues:
            обратнаяЦепочка.reversed().enumerated().map { ($0.element, $0.offset) })
    }

    private static func проверить(_ запись: ЗаписьИсторииМодели) throws {
        guard точнаяНепустаяСтрока(запись.идентификаторЗаписи),
              точнаяНепустаяСтрока(запись.идентификаторРешения),
              точнаяНепустаяСтрока(запись.узел),
              точнаяНепустаяСтрока(запись.ветка),
              точнаяНепустаяСтрока(запись.источникПолномочий),
              точнаяНепустаяСтрока(запись.причина) else {
            throw ОшибкаИсторииМодели.невернаяЗапись
        }
        try проверить(запись.инициатор)
        try проверить(запись.отправитель)
        if запись.вид == .наблюдение && запись.наблюдённыйПрофиль == nil {
            throw ОшибкаИсторииМодели.невернаяЗапись
        }
    }

    private static func проверить(_ субъект: СубъектИсторииМодели) throws {
        switch субъект.вид {
        case .человек, .агент:
            guard let идентификатор = субъект.идентификатор,
                  точнаяНепустаяСтрока(идентификатор) else {
                throw ОшибкаИсторииМодели.невернаяЗапись
            }
        case .неизвестен:
            guard субъект.идентификатор == nil else {
                throw ОшибкаИсторииМодели.невернаяЗапись
            }
        }
    }

    private static func точнаяНепустаяСтрока(_ значение: String) -> Bool {
        !значение.isEmpty
            && значение == значение.trimmingCharacters(in: .whitespacesAndNewlines)
    }
}

private func кодировщик() -> JSONEncoder {
    let кодировщик = JSONEncoder()
    кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
    return кодировщик
}

private func стабильныйХэш<T: Encodable>(_ значение: T) throws -> String {
    SHA256.hash(data: try кодировщик().encode(значение))
        .map { String(format: "%02x", $0) }.joined()
}


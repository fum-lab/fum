private enum СостояниеДобавленияИстории: String, Codable, Sendable {
    case новое, точныйПовтор, конфликт
}

private struct ВходИсторииFUMA: Codable, Sendable {
    let состояние: СостояниеДобавленияИстории
}

private struct РешениеИсторииFUMA: Codable, Sendable {
    let действие: ДействиеИсторииМодели
}

public enum ИсторияМоделиУзла {
    public static func спланироватьДобавление(
        _ история: [ЗаписьИсторииМодели],
        запись: ЗаписьИсторииМодели
    ) throws -> ПланДобавленияИсторииМодели {
        try проверить(запись)
        let совпадения = история.filter { $0.идентификаторЗаписи == запись.идентификаторЗаписи }
        let состояние: СостояниеДобавленияИстории
        if совпадения.isEmpty {
            состояние = .новое
        } else if совпадения.count == 1 && совпадения[0] == запись {
            состояние = .точныйПовтор
        } else {
            состояние = .конфликт
        }
        let определение = try ОпределениеОператора.разобрать(операторИстории)
        guard определение.идентификатор == "fum.спланировать-добавление-истории-модели",
              определение.шаги.count == 1,
              case .вычислитьJSON = определение.шаги[0].действие else {
            throw ОшибкаИсторииМодели.определениеFUMA
        }
        let вход = String(decoding: try кодировщик().encode(ВходИсторииFUMA(состояние: состояние)), as: UTF8.self)
        let исполнение = try AutomationExecutor.выполнить(определение, вход: .текст(вход))
        guard case .текст(let результат) = исполнение.результат else {
            throw ОшибкаИсторииМодели.определениеFUMA
        }
        let решение = try JSONDecoder().decode(РешениеИсторииFUMA.self, from: Data(результат.utf8))
        return ПланДобавленияИсторииМодели(действие: решение.действие, запись: запись)
    }

    public static func применить(
        _ план: ПланДобавленияИсторииМодели,
        к история: [ЗаписьИсторииМодели]
    ) throws -> [ЗаписьИсторииМодели] {
        let ожидаемый = try спланироватьДобавление(история, запись: план.запись)
        guard ожидаемый == план else { throw ОшибкаИсторииМодели.несогласованныйПлан }
        switch план.действие {
        case .добавить:
            return история + [план.запись]
        case .неДобавлятьПовтор:
            return история
        case .отказатьКонфликт:
            throw ОшибкаИсторииМодели.конфликтИдентификатора
        }
    }

    public static func текущийПрофиль(_ история: [ЗаписьИсторииМодели]) -> ПрофильМодели? {
        история.last(where: { $0.вид == .наблюдение && $0.наблюдённыйПрофиль != nil })?
            .наблюдённыйПрофиль
    }

    private static func проверить(_ запись: ЗаписьИсторииМодели) throws {
        guard !запись.идентификаторЗаписи.isEmpty,
              !запись.идентификаторРешения.isEmpty,
              !запись.узел.isEmpty,
              !запись.ветка.isEmpty,
              !запись.источникПолномочий.isEmpty,
              !запись.причина.isEmpty else {
            throw ОшибкаИсторииМодели.невернаяЗапись
        }
        if запись.инициатор.вид != .неизвестен && запись.инициатор.идентификатор == nil {
            throw ОшибкаИсторииМодели.невернаяЗапись
        }
        if запись.вид == .наблюдение && запись.наблюдённыйПрофиль == nil {
            throw ОшибкаИсторииМодели.невернаяЗапись
        }
    }
}

private func кодировщик() -> JSONEncoder {
    let кодировщик = JSONEncoder()
    кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
    return кодировщик
}

private func стабильныйХэш<T: Encodable>(_ значение: T) throws -> String {
    SHA256.hash(data: try кодировщик().encode(значение))
        .map { String(format: "%02x", $0) }.joined()
}


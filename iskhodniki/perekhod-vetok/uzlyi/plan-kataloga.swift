public struct ПланКаталогаВосстановления: Codable, Sendable {
    public let схема: String
    public let версия: Int
    public let хэшВхода: String
    public let запрос: ЗапросВосстановленияКаталога
    public let сеансы: [НаблюдениеСеансаКаталога]
    public let наблюденияРепозитория: [НаблюдениеРепозиторияКаталога]
    public let состояние: СостояниеПланаКаталога
    public let решения: [РешениеКаталога]
    public var идентификаторПлана: String
    public init(схема: String, версия: Int, хэшВхода: String, запрос: ЗапросВосстановленияКаталога,
                сеансы: [НаблюдениеСеансаКаталога], наблюденияРепозитория: [НаблюдениеРепозиторияКаталога],
                состояние: СостояниеПланаКаталога, решения: [РешениеКаталога], идентификаторПлана: String) {
        self.схема = схема; self.версия = версия; self.хэшВхода = хэшВхода; self.запрос = запрос; self.сеансы = сеансы
        self.наблюденияРепозитория = наблюденияРепозитория; self.состояние = состояние; self.решения = решения
        self.идентификаторПлана = идентификаторПлана
    }
    private enum CodingKeys: String, CodingKey, CaseIterable {
        case схема, версия, хэшВхода, запрос, сеансы, наблюденияРепозитория, состояние, решения, идентификаторПлана
    }
    public init(from декодировщик: any Decoder) throws {
        let контейнер = try контейнерЗакрытыхКлючей(декодировщик, ключи: CodingKeys.self)
        схема = try контейнер.decode(String.self, forKey: .схема); версия = try контейнер.decode(Int.self, forKey: .версия)
        хэшВхода = try контейнер.decode(String.self, forKey: .хэшВхода)
        запрос = try контейнер.decode(ЗапросВосстановленияКаталога.self, forKey: .запрос)
        сеансы = try контейнер.decode([НаблюдениеСеансаКаталога].self, forKey: .сеансы)
        наблюденияРепозитория = try контейнер.decode([НаблюдениеРепозиторияКаталога].self, forKey: .наблюденияРепозитория)
        состояние = try контейнер.decode(СостояниеПланаКаталога.self, forKey: .состояние)
        решения = try контейнер.decode([РешениеКаталога].self, forKey: .решения)
        идентификаторПлана = try контейнер.decode(String.self, forKey: .идентификаторПлана)
    }
    public func пересчитатьИдентификатор() throws -> String {
        try ХэшированиеКаталога.хэшSHA256(МатериалПланаКаталога(
            схема: схема, версия: версия, хэшВхода: хэшВхода, запрос: запрос, сеансы: сеансы,
            наблюденияРепозитория: наблюденияРепозитория, состояние: состояние, решения: решения
        ))
    }
    public func проверитьИдентификатор() -> Bool {
        (try? пересчитатьИдентификатор()) == идентификаторПлана
    }
}

private enum ХэшированиеКаталога {
    static func хэшSHA256<Значение: Encodable>(_ значение: Значение) throws -> String {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        let данные = try кодировщик.encode(значение)
        return SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
    }
}

public enum ПланировщикКаталогаВосстановления {
    // Источники наблюдений остаются утверждениями; чистый планировщик не удостоверяет их происхождение.
    public static func построить(
        _ запрос: ЗапросВосстановленияКаталога,
        сеансы: [НаблюдениеСеансаКаталога],
        наблюденияРепозитория: [НаблюдениеРепозиторияКаталога],
        контекст: КонтекстНаблюденийКаталога = .источникНедоступен,
        исходныеБайты: Data? = nil
    ) throws -> ПланКаталогаВосстановления {
        guard запрос.допуск.выбранныеДети.count <= 64, запрос.узлы.count <= 64,
              сеансы.count <= 128, наблюденияРепозитория.count <= 128,
              запрос.допуск.разрешённыеНовыеЭтапы.count <= 128
        else { throw ОтказКаталогаВосстановления.объём }
        let выбранныеДети = запрос.допуск.выбранныеДети
        var встреченные = Set<String>()
        let уникальныеДети = выбранныеДети.filter { встреченные.insert($0).inserted }
        let выбранноеМножество = Set(выбранныеДети)
        let частотаВыбора = Dictionary(grouping: выбранныеДети, by: { $0 }).mapValues { $0.count }
        let узлыПоИдентификатору = Dictionary(grouping: запрос.узлы, by: \.идентификатор)
        let выбранныеСеансы = сеансы.filter { выбранноеМножество.contains($0.узел) }
        let сеансыПоИдентификатору = Dictionary(grouping: выбранныеСеансы, by: \.узел)
        let выбранныеНаблюденияРепозитория = наблюденияРепозитория.filter { выбранноеМножество.contains($0.узел) }
        let наблюденияРепозиторияПоИдентификатору = Dictionary(grouping: выбранныеНаблюденияРепозитория, by: \.узел)
        let выбранныеУзлы = запрос.узлы.filter { выбранноеМножество.contains($0.идентификатор) }
        let поПути = Dictionary(grouping: выбранныеУзлы, by: \.целевойПуть)
        let поВетке = Dictionary(grouping: выбранныеУзлы, by: {
            КлючВеткиКаталога(репозиторий: $0.репозиторийИсточника, ветка: $0.ветка)
        })
        var конфликтующиеУзлы = Set<String>()
        for группа in Array(поПути.values) + Array(поВетке.values) {
            let идентификаторы = Set(группа.map(\.идентификатор))
            if идентификаторы.count > 1 { конфликтующиеУзлы.formUnion(идентификаторы) }
        }
        let разрешенияПоУзлу = Dictionary(grouping: запрос.допуск.разрешённыеНовыеЭтапы, by: \.узел)

        let допускКорректен =
            запрос.схемаДанных == ЗапросВосстановленияКаталога.схема &&
            запрос.версия == 1 && !запрос.допуск.идентификатор.isEmpty &&
            корректныйUUID(запрос.допуск.координатор) &&
            корректныйUUID(запрос.допуск.корневаяЗадача) &&
            !выбранныеДети.isEmpty && выбранныеДети.count <= 64 && запрос.узлы.count <= 64 &&
            сеансы.count <= 128 && наблюденияРепозитория.count <= 128 &&
            запрос.допуск.разрешённыеНовыеЭтапы.count <= 128 && корректенИсточник(запрос.источник)

        var решения: [РешениеКаталога] = []
        for идентификатор in уникальныеДети {
            let узлы = узлыПоИдентификатору[идентификатор] ?? []
            let записиСеанса = сеансыПоИдентификатору[идентификатор] ?? []
            let записиРепозитория = наблюденияРепозиторияПоИдентификатору[идентификатор] ?? []
            let узел = узлы.count == 1 ? узлы[0] : nil
            let наблюдениеРепозитория = записиРепозитория.count == 1 ? записиРепозитория[0] : nil

            if контекст.режим == .закрытый {
                решения.append(try собрать(узел: идентификатор, состояние: .заблокировано,
                    действие: .наблюдать, причина: .источникНаблюденийНеПодключён,
                    модельУзла: узел, наблюдениеРепозитория: наблюдениеРепозитория, допуск: запрос.допуск.идентификатор))
            } else if !допускКорректен {
                решения.append(try собрать(узел: идентификатор, состояние: .заблокировано,
                    действие: .наблюдать, причина: .областьНеСовпадает,
                    модельУзла: узел, наблюдениеРепозитория: наблюдениеРепозитория, допуск: запрос.допуск.идентификатор))
            } else if конфликтующиеУзлы.contains(идентификатор) || частотаВыбора[идентификатор] != 1 || узлы.count != 1 ||
                      записиСеанса.count > 1 || записиРепозитория.count > 1 {
                решения.append(try собрать(узел: идентификатор, состояние: .неизвестно,
                    действие: .наблюдать, причина: .снимокНеоднозначен,
                    модельУзла: узел, наблюдениеРепозитория: наблюдениеРепозитория, допуск: запрос.допуск.идентификатор))
            } else if let узел, !корректенУзел(узел) ||
                        узел.родитель != запрос.допуск.координатор {
                решения.append(try собрать(узел: идентификатор, состояние: .заблокировано,
                    действие: .наблюдать, причина: .областьНеСовпадает,
                    модельУзла: узел, наблюдениеРепозитория: наблюдениеРепозитория, допуск: запрос.допуск.идентификатор))
            } else if let узел, let сеанс = записиСеанса.first {
                решения.append(try решить(узел: узел, сеанс: сеанс,
                    наблюдениеРепозитория: наблюдениеРепозитория, допуск: запрос.допуск,
                    разрешения: разрешенияПоУзлу[идентификатор] ?? [], контекст: контекст))
            } else {
                решения.append(try собрать(узел: идентификатор, состояние: .неизвестно,
                    действие: .наблюдать, причина: .свидетельствНедостаточно,
                    модельУзла: узел, наблюдениеРепозитория: наблюдениеРепозитория, допуск: запрос.допуск.идентификатор))
            }
        }

        let состояниеПлана: СостояниеПланаКаталога =
            контекст.режим == .доверенныйТестовый && !уникальныеДети.isEmpty && решения.allSatisfy { $0.состояние != .неизвестно }
            ? .полныйСнимок : .неполныйСнимок
        var план = ПланКаталогаВосстановления(
            схема: "fuma.план-восстановления-каталога.1", версия: 1,
            хэшВхода: try исходныеБайты.map { SHA256.hash(data: $0).map { String(format: "%02x", $0) }.joined() }
                ?? ХэшированиеКаталога.хэшSHA256(запрос), запрос: запрос,
            сеансы: выбранныеСеансы, наблюденияРепозитория: выбранныеНаблюденияРепозитория,
            состояние: состояниеПлана, решения: решения, идентификаторПлана: ""
        )
        план.идентификаторПлана = try план.пересчитатьИдентификатор()
        return план
    }

    private static func решить(
        узел: УзелКаталогаВосстановления, сеанс: НаблюдениеСеансаКаталога,
        наблюдениеРепозитория: НаблюдениеРепозиторияКаталога?, допуск: ДопускКаталогаВосстановления,
        разрешения: [РазрешённыйЭтапКаталога], контекст: КонтекстНаблюденийКаталога
    ) throws -> РешениеКаталога {
        func итог(_ состояние: СостояниеРешенияКаталога, _ действие: ДействиеКаталога,
                  _ причина: ПричинаРешенияКаталога) throws -> РешениеКаталога {
            try собрать(узел: узел.идентификатор, состояние: состояние, действие: действие,
                        причина: причина, модельУзла: узел, наблюдениеРепозитория: наблюдениеРепозитория,
                        допуск: допуск.идентификатор,
                        этап: действие == .возобновитьТотЖеУзел ? сеанс.этап : nil,
                        поручениеЭтапа: действие == .возобновитьТотЖеУзел
                            ? разрешения.first(where: { $0.этап == сеанс.этап })?.поручение : nil)
        }

        guard непустое(сеанс.источник), непустое(сеанс.время), непустое(сеанс.версия),
              let наблюдаемыйУзел = сеанс.наблюдаемыйУзел else {
            return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
        }
        let форматВремени = ISO8601DateFormatter()
        guard let строкаВремени = сеанс.время, let время = форматВремени.date(from: строкаВремени),
              контекст.срокДействия.isFinite, контекст.срокДействия > 0,
              время <= контекст.время, контекст.время.timeIntervalSince(время) <= контекст.срокДействия else {
            return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
        }
        guard наблюдаемыйУзел == узел.идентификатор else {
            return try итог(.заблокировано, .наблюдать, .идентификаторНеСовпадает)
        }
        if сеанс.владелец == .чужой { return try итог(.заблокировано, .наблюдать, .владелецЧужой) }
        guard сеанс.владелец == .свой else { return try итог(.неизвестно, .наблюдать, .владелецНеизвестен) }

        switch сеанс.состояние {
        case .приостановлен: return try итог(.приостановлено, .наблюдать, .паузаНеОткрываетЗадачу)
        case .отменён: return try итог(.отменено, .наблюдать, .отменаНеОткрываетЗадачу)
        case .завершённыйЭтап: return try итог(.заблокировано, .наблюдать, .завершённыйЭтапНеОткрывается)
        case .неизвестно: return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
        default: break
        }
        let запускНеизвестен = сеанс.состояние == .запускНеизвестен
        let ожидаетСоставителя = сеанс.состояние == .ожидаетСоставителя
        let новыйЭтап = сеанс.состояние == .новыйРазрешённыйЭтап
        if новыйЭтап {
            let этапы = Dictionary(grouping: разрешения, by: \.этап)
            if этапы.values.contains(where: { $0.count != 1 }) {
                return try итог(.неизвестно, .наблюдать, .снимокНеоднозначен)
            }
            guard let этап = сеанс.этап, let разрешение = этапы[этап]?.first,
                  разрешение.узел == узел.идентификатор, непустое(разрешение.поручение) else {
                return try итог(.заблокировано, .наблюдать, .этапНеРазрешён)
            }
        }
        guard let наблюдениеРепозитория else { return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно) }
        if наблюдениеРепозитория.наличиеВетки == .неизвестно {
            return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
        }
        if наблюдениеРепозитория.наличиеВетки == .нет {
            return try итог(.заблокировано, .наблюдать, .веткаЗанятаИлиОтсутствует)
        }
        guard наблюдениеРепозитория.репозиторий == узел.репозиторийИсточника else {
            return try итог(.заблокировано, .наблюдать, .дрейфСостояния)
        }
        if наблюдениеРепозитория.состояниеФизическогоПути == .неизвестно ||
           наблюдениеРепозитория.регистрация == .неизвестно ||
           наблюдениеРепозитория.другиеРабочиеДеревья == .неизвестно {
            return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
        }
        if наблюдениеРепозитория.другиеРабочиеДеревья == .есть {
            return try итог(.заблокировано, .наблюдать, .веткаЗанятаИлиОтсутствует)
        }
        guard наблюдениеРепозитория.веткаИсточника != nil,
              наблюдениеРепозитория.коммитИсточника != nil, наблюдениеРепозитория.деревоИсточника != nil else {
            return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
        }
        guard наблюдениеРепозитория.веткаИсточника == узел.ветка,
              наблюдениеРепозитория.коммитИсточника == узел.коммит,
              наблюдениеРепозитория.деревоИсточника == узел.дерево else {
            return try итог(.заблокировано, .наблюдать, .дрейфСостояния)
        }
        if наблюдениеРепозитория.отслеживаемыеФайлы == .грязно {
            return try итог(.заблокировано, .наблюдать, .грязныеОтслеживаемыеФайлы)
        }
        if наблюдениеРепозитория.неотслеживаемыеФайлы == .есть {
            return try итог(.заблокировано, .наблюдать, .неотслеживаемыеФайлыЕсть)
        }
        if наблюдениеРепозитория.неотслеживаемыеФайлы == .неизвестно {
            return try итог(.неизвестно, .наблюдать, .неотслеживаемыеФайлыНеизвестны)
        }
        if запускНеизвестен && наблюдениеРепозитория.фаза != .послеЧтенияРепозитория {
            return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
        }

        if наблюдениеРепозитория.состояниеФизическогоПути == .есть &&
           наблюдениеРепозитория.регистрация == .есть {
            guard let физическийПуть = наблюдениеРепозитория.физическийПуть else {
                return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
            }
            guard физическийПуть == узел.целевойПуть else {
                return try итог(.заблокировано, .наблюдать, .дрейфСостояния)
            }
            guard let владелецРегистрации = наблюдениеРепозитория.владелецРегистрации else {
                return try итог(.неизвестно, .наблюдать, .владелецНеизвестен)
            }
            guard владелецРегистрации == узел.идентификатор else {
                return try итог(.заблокировано, .наблюдать, .владелецЧужой)
            }
            guard наблюдениеРепозитория.наличиеВетки != .неизвестно,
                  наблюдениеРепозитория.ветка != nil, наблюдениеРепозитория.коммит != nil, наблюдениеРепозитория.дерево != nil else {
                return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
            }
            guard наблюдениеРепозитория.наличиеВетки == .есть,
                  наблюдениеРепозитория.ветка == узел.ветка, наблюдениеРепозитория.коммит == узел.коммит,
                  наблюдениеРепозитория.дерево == узел.дерево else {
                return try итог(.заблокировано, .наблюдать, .дрейфСостояния)
            }
            guard наблюдениеРепозитория.отслеживаемыеФайлы == .чисто else {
                return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
            }
            if сеанс.состояние == .активен { return try итог(.активно, .ничегоНеМенять, .ужеАктивен) }
            if запускНеизвестен || ожидаетСоставителя || сеанс.состояние == .готов {
                return try итог(.готово, .ничегоНеМенять,
                                запускНеизвестен ? .свидетельствНедостаточно : .точноеСуществующееСостояние)
            }
            if новыйЭтап && наблюдениеРепозитория.фаза == .послеЧтенияРепозитория {
                return try итог(.готово, .возобновитьТотЖеУзел, .точноеСуществующееСостояние)
            }
            return try итог(.готово, .ничегоНеМенять, .требуетсяЧтениеРепозитория)
        }

        if наблюдениеРепозитория.состояниеФизическогоПути == .нет &&
           наблюдениеРепозитория.регистрация == .нет {
            if let путь = наблюдениеРепозитория.физическийПуть, путь != узел.целевойПуть {
                return try итог(.заблокировано, .наблюдать, .дрейфСостояния)
            }
            if наблюдениеРепозитория.владелецРегистрации != nil {
                return try итог(.заблокировано, .наблюдать, .владелецЧужой)
            }
            if сеанс.состояние == .активен || запускНеизвестен ||
               наблюдениеРепозитория.фаза != .доЭффекта {
                return try итог(.неизвестно, .наблюдать,
                                наблюдениеРепозитория.фаза == .послеЧтенияРепозитория
                                    ? .послеЧтенияЦельОтсутствует : .свидетельствНедостаточно)
            }
            if узел.роль == .постоянная && !новыйЭтап && !ожидаетСоставителя {
                return try итог(.заблокировано, .наблюдать, .этапНеРазрешён)
            }
            guard сеанс.состояние == .готов || новыйЭтап || ожидаетСоставителя else {
                return try итог(.неизвестно, .наблюдать, .свидетельствНедостаточно)
            }
            return try итог(.готово, .восстановитьОтслеживаемое, .готовКВосстановлению)
        }
        return try итог(.заблокировано, .наблюдать, .дрейфСостояния)
    }

    private static func собрать(
        узел идентификатор: String, состояние: СостояниеРешенияКаталога,
        действие: ДействиеКаталога, причина: ПричинаРешенияКаталога,
        модельУзла: УзелКаталогаВосстановления?, наблюдениеРепозитория: НаблюдениеРепозиторияКаталога?,
        допуск: String, этап: String? = nil, поручениеЭтапа: String? = nil
    ) throws -> РешениеКаталога {
        let путь = модельУзла?.целевойПуть ?? наблюдениеРепозитория?.физическийПуть
        let ветка = модельУзла?.ветка ?? наблюдениеРепозитория?.веткаИсточника ?? наблюдениеРепозитория?.ветка
        let коммит = модельУзла?.коммит ?? наблюдениеРепозитория?.коммитИсточника ?? наблюдениеРепозитория?.коммит
        let дерево = модельУзла?.дерево ?? наблюдениеРепозитория?.деревоИсточника ?? наблюдениеРепозитория?.дерево
        let намерение = try ХэшированиеКаталога.хэшSHA256(МатериалНамеренияКаталога(
            допуск: допуск, узел: идентификатор, действие: действие.rawValue,
            целевойПуть: путь, ветка: ветка, коммит: коммит, дерево: дерево,
            этап: этап, поручениеЭтапа: поручениеЭтапа
        ))
        return РешениеКаталога(
            узел: идентификатор, состояние: состояние, действие: действие, причина: причина,
            намерение: намерение, целевойПуть: путь,
            репозиторийИсточника: модельУзла?.репозиторийИсточника ?? наблюдениеРепозитория?.репозиторий
        )
    }

    private static func корректныйUUID(_ значение: String) -> Bool {
        guard let узелUUID = UUID(uuidString: значение) else { return false }
        return узелUUID.uuidString.lowercased() == значение
    }
    private static func корректныйOID(_ значение: String) -> Bool {
        (значение.count == 40 || значение.count == 64) &&
        значение == значение.lowercased() &&
        значение.unicodeScalars.allSatisfy { CharacterSet(charactersIn: "0123456789abcdef").contains($0) }
    }
    // Это предварительная синтаксическая защита; production adapter обязан вызвать git check-ref-format для точной ветки.
    private static func корректнаяВетка(_ значение: String) -> Bool {
        guard значение.hasPrefix("refs/heads/"), значение != "@", !значение.hasSuffix("/"),
              !значение.contains(".."), !значение.contains("@{"), !значение.contains("//"),
              !значение.hasSuffix(".") else { return false }
        let запрещённые = CharacterSet(charactersIn: " \u{7e}^:?*[\\").union(.controlCharacters)
        guard значение.unicodeScalars.allSatisfy({ !запрещённые.contains($0) && $0.value != 127 }) else {
            return false
        }
        return значение.split(separator: "/", omittingEmptySubsequences: false).allSatisfy {
            !$0.isEmpty && !$0.hasPrefix(".") && !$0.hasSuffix(".lock")
        }
    }
    private static func непустое(_ значение: String?) -> Bool {
        guard let значение else { return false }
        return !значение.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
    private static func корректенИсточник(_ источник: ИсточникДопускаКаталога) -> Bool {
        корректныйOID(источник.коммит) && корректныйOID(источник.дерево) &&
        корректныйOID(источник.объект) && источник.хэш.count == 64 &&
        источник.хэш == источник.хэш.lowercased() &&
        источник.хэш.unicodeScalars.allSatisfy {
            CharacterSet(charactersIn: "0123456789abcdef").contains($0)
        } && непустое(источник.путь)
    }
    private static func корректенУзел(_ узел: УзелКаталогаВосстановления) -> Bool {
        корректныйUUID(узел.идентификатор) && корректныйUUID(узел.родитель) &&
        корректнаяВетка(узел.ветка) && корректныйOID(узел.коммит) && корректныйOID(узел.дерево) &&
        корректенАбсолютныйПуть(узел.целевойПуть) && корректенАбсолютныйПуть(узел.репозиторийИсточника)
    }
    private static func корректенАбсолютныйПуть(_ путь: String) -> Bool {
        путь.hasPrefix("/") && путь.utf8.count <= 4096 &&
        !путь.unicodeScalars.contains(where: CharacterSet.controlCharacters.contains) &&
        URL(fileURLWithPath: путь).standardizedFileURL.path == путь
    }

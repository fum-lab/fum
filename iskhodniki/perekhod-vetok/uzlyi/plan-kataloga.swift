public struct РешениеКаталога: Codable, Sendable {
    public let узел: String
    public let состояние: СостояниеРешенияКаталога
    public let действие: ДействиеКаталога
    public let причина: ПричинаРешенияКаталога
    public let намерение: String
    public let целевойПуть, репозиторийИсточника: String?
    public let неВосстанавливаемое: СостояниеНевосстанавливаемого
    public init(узел: String, состояние: СостояниеРешенияКаталога, действие: ДействиеКаталога,
                причина: ПричинаРешенияКаталога, намерение: String, целевойПуть: String?,
                репозиторийИсточника: String?, неВосстанавливаемое: СостояниеНевосстанавливаемого = .неизвестно) {
        self.узел = узел; self.состояние = состояние; self.действие = действие; self.причина = причина
        self.намерение = намерение; self.целевойПуть = целевойПуть
        self.репозиторийИсточника = репозиторийИсточника; self.неВосстанавливаемое = неВосстанавливаемое
    }
    private enum CodingKeys: String, CodingKey, CaseIterable {
        case узел, состояние, действие, причина, намерение, целевойПуть, репозиторийИсточника, неВосстанавливаемое
    }
    public init(from декодировщик: any Decoder) throws {
        let контейнер = try контейнерЗакрытыхКлючей(декодировщик, ключи: CodingKeys.self)
        узел = try контейнер.decode(String.self, forKey: .узел)
        состояние = try контейнер.decode(СостояниеРешенияКаталога.self, forKey: .состояние)
        действие = try контейнер.decode(ДействиеКаталога.self, forKey: .действие)
        причина = try контейнер.decode(ПричинаРешенияКаталога.self, forKey: .причина)
        намерение = try контейнер.decode(String.self, forKey: .намерение)
        целевойПуть = try контейнер.decodeIfPresent(String.self, forKey: .целевойПуть)
        репозиторийИсточника = try контейнер.decodeIfPresent(String.self, forKey: .репозиторийИсточника)
        неВосстанавливаемое = try контейнер.decode(СостояниеНевосстанавливаемого.self, forKey: .неВосстанавливаемое)
    }
    public func encode(to кодировщик: any Encoder) throws {
        var контейнер = кодировщик.container(keyedBy: CodingKeys.self)
        try контейнер.encode(узел, forKey: .узел); try контейнер.encode(состояние, forKey: .состояние)
        try контейнер.encode(действие, forKey: .действие); try контейнер.encode(причина, forKey: .причина)
        try контейнер.encode(намерение, forKey: .намерение)
        try контейнер.encode(целевойПуть as String?, forKey: .целевойПуть)
        try контейнер.encode(репозиторийИсточника as String?, forKey: .репозиторийИсточника)
        try контейнер.encode(неВосстанавливаемое, forKey: .неВосстанавливаемое)
    }
}

public struct КонтекстНаблюденийКаталога: Sendable {
    enum Режим: Sendable, Equatable { case закрытый, доверенныйТестовый }
    let режим: Режим
    let время: Date
    let срокДействия: TimeInterval
    private init(_ режим: Режим, время: Date, срокДействия: TimeInterval) {
        self.режим = режим; self.время = время; self.срокДействия = срокДействия
    }
    public static let источникНедоступен = КонтекстНаблюденийКаталога(
        .закрытый, время: Date(timeIntervalSince1970: 0), срокДействия: 0)
    // Видно тестовому модулю через @testable import; отсутствует в JSON.
    static let доверенныйТестовый = КонтекстНаблюденийКаталога(
        .доверенныйТестовый, время: Date(timeIntervalSince1970: 1_793_008_800), срокДействия: 60)
    static func тестовый(время: Date, срокДействия: TimeInterval = 60) -> Self {
        Self(.доверенныйТестовый, время: время, срокДействия: срокДействия)
    }
}


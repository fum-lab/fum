/// Разбирает поле author в первом блоке заголовков сырых байтов коммита.
/// Ожидаемую личность и Git-происхождение проверяет вызывающий адаптер.
enum РазборАвтораСырогоКоммита {
    static func извлечьИмя(_ байтыКоммита: Data) throws -> String {
        guard байтыКоммита.count <= ПределыПроверкиПубликации.сыройКоммит else {
            throw ОтказПроверкиПубликации.сыройКоммитСлишкомВелик
        }
        let байты = Array(байтыКоммита)
        guard let граница = (0..<max(байты.count - 1, 0)).first(where: {
            байты[$0] == 0x0a && байты[$0 + 1] == 0x0a
        }),
        let заголовок = String(data: Data(байты[..<граница]), encoding: .utf8)
        else { throw ОтказПроверкиПубликации.заголовокСырогоКоммитаНекорректен }

        let строкиАвтора = заголовок.split(separator: "\n", omittingEmptySubsequences: false)
            .filter { $0.hasPrefix("author ") }
        guard строкиАвтора.count == 1 else {
            throw ОтказПроверкиПубликации.заголовокСырогоКоммитаНекорректен
        }

        let значение = строкиАвтора[0].dropFirst("author ".count)
        guard let началоПочты = значение.range(of: " <"),
              let конецПочты = значение[началоПочты.upperBound...].firstIndex(of: ">"),
              началоПочты.lowerBound != значение.startIndex,
              конецПочты > началоПочты.upperBound
        else { throw ОтказПроверкиПубликации.заголовокСырогоКоммитаНекорректен }
        return String(значение[..<началоПочты.lowerBound])
    }
}

/// Сверяет разобранное имя только с уже проверенным источником личности этапа.
enum ПроверкаАвтораСырогоКоммита {
    static func проверить(_ байтыКоммита: Data, поПути путь: ПроверенныйПутьКодекс) throws {
        let фактическоеИмя = try РазборАвтораСырогоКоммита.извлечьИмя(байтыКоммита)
        guard фактическоеИмя == путь.ожидаемоеИмяАвтора else {
            throw ОтказПроверкиПубликации.авторСырогоКоммитаНеСовпадает
        }
    }
}

enum ПроверкаТелаСырогоКоммита {
    static func проверить(_ байтыКоммита: Data, поПути путь: ПроверенныйПутьКодекс) throws {
        guard байтыКоммита.count <= ПределыПроверкиПубликации.сыройКоммит,
              let граница = байтыКоммита.range(of: Data([0x0a, 0x0a]))
        else { throw ОтказПроверкиПубликации.телоСырогоКоммитаНеСовпадает }
        let фактическоеТело = Data(байтыКоммита[граница.upperBound...])
        guard фактическоеТело == Data(путь.телоСообщенияДляПроверкиСырогоКоммита.utf8) else {
            throw ОтказПроверкиПубликации.телоСырогоКоммитаНеСовпадает
        }
    }
}

public struct КвитанцияПроверкиАвтораИТелаСырогоКоммита: Codable, Equatable, Sendable {
    public let схема: String
    public let идентификаторОбъекта: String
    public let идентификаторКорневойЗадачи: String
    public let идентификаторЭтапа: String
    public let идентификаторСнимка: String
    public let модель: String
    public let усилие: String
    public let имяАвтора: String
    public let хэшСырогоКоммита: String
    public let точныеБайтыПроверены: Bool
    public let побочныйЭффект: String
    public let источникМоделиАутентифицирован: Bool

    fileprivate init(
        идентификаторОбъекта: String, снимок: СнимокИдентичностиКодекс,
        имяАвтора: String, хэшСырогоКоммита: String
    ) {
        схема = "fum.codex-raw-commit-author-body-check.2"
        self.идентификаторОбъекта = идентификаторОбъекта
        идентификаторКорневойЗадачи = снимок.этап.идентификаторКорневойЗадачи
        идентификаторЭтапа = снимок.этап.идентификаторЭтапа
        идентификаторСнимка = снимок.идентификаторСнимка
        модель = снимок.модель
        усилие = снимок.усилие
        self.имяАвтора = имяАвтора
        self.хэшСырогоКоммита = хэшСырогоКоммита
        точныеБайтыПроверены = true
        побочныйЭффект = "нет"
        источникМоделиАутентифицирован = false
    }

    public init(from декодер: Decoder) throws {
        let контейнер = try декодер.container(keyedBy: КлючДанных.self)
        try проверитьЗакрытыйНаборКлючей(контейнер, ожидаемые: [
            "схема", "oid", "rootUUID", "stageUUID", "snapshotUUID", "модель",
            "усилие", "имяАвтора", "sha256СырогоКоммита", "точныеБайтыПроверены",
            "побочныйЭффект", "источникМоделиАутентифицирован",
        ], декодер: декодер)
        схема = try контейнер.decode(String.self, forKey: ключДанных("схема"))
        идентификаторОбъекта = try контейнер.decode(String.self, forKey: ключДанных("oid"))
        идентификаторКорневойЗадачи = try контейнер.decode(String.self, forKey: ключДанных("rootUUID"))
        идентификаторЭтапа = try контейнер.decode(String.self, forKey: ключДанных("stageUUID"))
        идентификаторСнимка = try контейнер.decode(String.self, forKey: ключДанных("snapshotUUID"))
        модель = try контейнер.decode(String.self, forKey: ключДанных("модель"))
        усилие = try контейнер.decode(String.self, forKey: ключДанных("усилие"))
        имяАвтора = try контейнер.decode(String.self, forKey: ключДанных("имяАвтора"))
        хэшСырогоКоммита = try контейнер.decode(String.self, forKey: ключДанных("sha256СырогоКоммита"))
        точныеБайтыПроверены = try контейнер.decode(Bool.self, forKey: ключДанных("точныеБайтыПроверены"))
        побочныйЭффект = try контейнер.decode(String.self, forKey: ключДанных("побочныйЭффект"))
        источникМоделиАутентифицирован = try контейнер.decode(
            Bool.self, forKey: ключДанных("источникМоделиАутентифицирован"))
    }

    public func encode(to кодировщик: Encoder) throws {
        var контейнер = кодировщик.container(keyedBy: КлючДанных.self)
        try контейнер.encode(схема, forKey: ключДанных("схема"))
        try контейнер.encode(идентификаторОбъекта, forKey: ключДанных("oid"))
        try контейнер.encode(идентификаторКорневойЗадачи, forKey: ключДанных("rootUUID"))
        try контейнер.encode(идентификаторЭтапа, forKey: ключДанных("stageUUID"))
        try контейнер.encode(идентификаторСнимка, forKey: ключДанных("snapshotUUID"))
        try контейнер.encode(модель, forKey: ключДанных("модель"))
        try контейнер.encode(усилие, forKey: ключДанных("усилие"))
        try контейнер.encode(имяАвтора, forKey: ключДанных("имяАвтора"))
        try контейнер.encode(хэшСырогоКоммита, forKey: ключДанных("sha256СырогоКоммита"))
        try контейнер.encode(точныеБайтыПроверены, forKey: ключДанных("точныеБайтыПроверены"))
        try контейнер.encode(побочныйЭффект, forKey: ключДанных("побочныйЭффект"))
        try контейнер.encode(
            источникМоделиАутентифицирован,
            forKey: ключДанных("источникМоделиАутентифицирован"))
    }
}

/// Читает только переданные документы и сырые байты коммита; источник модели проверяет вызывающая сторона.
public enum ПроверкаВыбранногоАвторстваИТелаКодекс {
    public static func проверить(
        данныеСнимка: Data,
        данныеВыбораИсточника: Data,
        данныеОжидаемогоЭтапа: Data,
        данныеСообщения: Data,
        идентификаторОбъекта: String,
        байтыСырогоКоммита: Data
    ) throws -> КвитанцияПроверкиАвтораИТелаСырогоКоммита {
        guard [данныеСнимка, данныеВыбораИсточника, данныеОжидаемогоЭтапа, данныеСообщения]
            .allSatisfy({ $0.count <= ПределыПроверкиПубликации.документ })
        else { throw ОтказПроверкиПубликации.входнойДокументСлишкомВелик }
        guard байтыСырогоКоммита.count <= ПределыПроверкиПубликации.сыройКоммит else {
            throw ОтказПроверкиПубликации.сыройКоммитСлишкомВелик
        }
        guard полныйИдентификаторОбъекта(идентификаторОбъекта) else {
            throw ОтказПроверкиПубликации.ожидаемыйИдентификаторОбъектаНекорректен
        }
        guard let этап = try? JSONDecoder().decode(
            ЭтапСодержимогоКодекс.self, from: данныеОжидаемогоЭтапа)
        else { throw ОтказПроверкиПубликации.чужойИсточникЭтапа }

        let связывание = try ВалидаторЛичностиИСообщенияКодекс.проверитьВыбранныйИсточник(
            данныеСнимка: данныеСнимка, данныеВыбора: данныеВыбораИсточника,
            ожидаемыйЭтап: этап)
        let ожидаемаяИдентичность = try ВалидаторЛичностиИСообщенияКодекс.ожиданиеИдентичности(
            по: связывание)
        let проверенныйПуть = try ВалидаторЛичностиИСообщенияКодекс.проверить(
            связывание: связывание,
            данныеОжидаемойИдентичности: ожидаемаяИдентичность,
            данныеСообщения: данныеСообщения)
        try ПроверкаАвтораСырогоКоммита.проверить(байтыСырогоКоммита, поПути: проверенныйПуть)
        try ПроверкаТелаСырогоКоммита.проверить(байтыСырогоКоммита, поПути: проверенныйПуть)

        let вычисленныйИдентификаторОбъекта = идентификаторСодержимогоКоммита(байтыСырогоКоммита, длина: идентификаторОбъекта.count)
        guard вычисленныйИдентификаторОбъекта == идентификаторОбъекта else {
            throw ОтказПроверкиПубликации.идентификаторСырогоКоммитаНеСовпадает
        }
        let снимок = try JSONDecoder().decode(СнимокИдентичностиКодекс.self, from: данныеСнимка)
        return КвитанцияПроверкиАвтораИТелаСырогоКоммита(
            идентификаторОбъекта: идентификаторОбъекта, снимок: снимок, имяАвтора: проверенныйПуть.ожидаемоеИмяАвтора,
            хэшСырогоКоммита: SHA256.hash(data: байтыСырогоКоммита)
                .map { String(format: "%02x", $0) }.joined())
    }

    private static func полныйИдентификаторОбъекта(_ значение: String) -> Bool {
        (значение.count == 40 || значение.count == 64)
            && значение == значение.lowercased()
            && значение.allSatisfy(\.isHexDigit)
    }

    private static func идентификаторСодержимогоКоммита(_ байты: Data, длина: Int) -> String? {
        var объектКоммита = Data("commit \(байты.count)\0".utf8)
        объектКоммита.append(байты)
        if длина == 40 {
            return Insecure.SHA1.hash(data: объектКоммита)
                .map { String(format: "%02x", $0) }.joined()
        }
        guard длина == 64 else { return nil }
        return SHA256.hash(data: объектКоммита)
            .map { String(format: "%02x", $0) }.joined()
    }
}

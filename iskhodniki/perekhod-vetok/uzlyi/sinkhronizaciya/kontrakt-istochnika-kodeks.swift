            исходнаяСсылка: исходнаяСсылка, исходныйИдентификаторОбъекта: исходныйИдентификаторОбъекта,
            исходноеДерево: исходноеДерево, входящийИдентификаторОбъекта: входящийИдентификаторОбъекта,
            сообщение: сообщение)
        guard содержимоеЭтапа.схема == ЭтапСодержимогоКодекс.схемаДанных,
              содержимоеЭтапа.идентификаторКорневойЗадачи == сообщение.идентификаторКорневойЗадачи,
              действительныйУниверсальныйИдентификатор(идентификаторКорневойЗадачи), действительныйУниверсальныйИдентификатор(идентификаторЭтапа),
              операция == "ordinary" || операция == "merge",
              действительнаяСсылка(исходнаяСсылка), полныйИдентификаторОбъекта(исходныйИдентификаторОбъекта), полныйИдентификаторОбъекта(исходноеДерево),
              входящийИдентификаторОбъекта.map(полныйИдентификаторОбъекта) ?? true,
              (операция == "merge") == (входящийИдентификаторОбъекта != nil)
        else { throw ОтказПроверкиПубликации.чужойИсточникЭтапа }
        return содержимоеЭтапа
    }

    static func закодироватьСнимок(_ снимок: СнимокИдентичностиКодекс) throws -> Data {

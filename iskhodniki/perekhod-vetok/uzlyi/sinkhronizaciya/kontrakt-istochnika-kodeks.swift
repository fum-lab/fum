    static func проверить(
        связывание: ПроверенноеСвязываниеИсточникаКодекс,
        данныеОжидаемойИдентичности: Data,
        данныеСообщения: Data
    ) throws -> ПроверенныйПутьКодекс {
        guard данныеОжидаемойИдентичности.count <= ПределыПроверкиПубликации.документ,
              данныеСообщения.count <= ПределыПроверкиПубликации.документ,
              let ожидаемаяИдентичность = try? JSONDecoder().decode(
                ОжидаемаяИдентичностьКодекс.self, from: данныеОжидаемойИдентичности),
              let сообщение = try? JSONDecoder().decode(СообщениеКоммитаКодекс.self, from: данныеСообщения)
        else { throw ОтказПроверкиПубликации.личностьНеСовпала }

        let снимок = связывание.снимок
        guard ожидаемаяИдентичность.схема == ОжидаемаяИдентичностьКодекс.схемаДанных,
              ожидаемаяИдентичность.модель == снимок.модель,
              ожидаемаяИдентичность.усилие == снимок.усилие,
              ожидаемаяИдентичность.идентификаторКорневойЗадачи == снимок.этап.идентификаторКорневойЗадачи,
              ожидаемаяИдентичность.идентификаторСнимка == снимок.идентификаторСнимка,
              ожидаемаяИдентичность.хэшСнимка == связывание.хэшСнимка,
              ожидаемаяИдентичность.этап == связывание.этап,
              ожидаемаяИдентичность.наблюденоВМиллисекундах == снимок.наблюденоВМиллисекундах
        else { throw ОтказПроверкиПубликации.личностьНеСовпала }
        guard сообщение.схема == СообщениеКоммитаКодекс.схемаДанных,
              сообщение.идентификаторКорневойЗадачи == снимок.этап.идентификаторКорневойЗадачи,
              сообщение.модель == снимок.модель,
              сообщение.усилие == снимок.усилие,
              корректноеСообщение(сообщение)
        else { throw ОтказПроверкиПубликации.сообщениеНеполное }

        let пересчитанныйЭтап = try сформироватьЭтап(
            идентификаторКорневойЗадачи: снимок.этап.идентификаторКорневойЗадачи,
            идентификаторЭтапа: снимок.этап.идентификаторЭтапа,
            операция: снимок.этап.операция,
            исходнаяСсылка: снимок.этап.исходнаяСсылка,
            исходныйИдентификаторОбъекта: снимок.этап.исходныйИдентификаторОбъекта,
            исходноеДерево: снимок.этап.исходноеДерево,
            входящийИдентификаторОбъекта: снимок.этап.входящийИдентификаторОбъекта,
            сообщение: сообщение)
        guard пересчитанныйЭтап == связывание.этап else {
            throw ОтказПроверкиПубликации.источникПодменён
        }
        return ПроверенныйПутьКодекс(
            ожидаемаяЛичность: ожидаемаяИдентичность, сообщение: сообщение,
            связывание: связывание, этап: пересчитанныйЭтап,
            имяАвтора: "FUM Codex [\(снимок.модель); effort=\(снимок.усилие)]",
            полныйТекст: сообщение.полныйТекст)
    }


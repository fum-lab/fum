    static func подтвердить(
        _ кандидат: КандидатПодготовкиЗапускаКодекс,
        наблюдённыйКонтекст: НаблюдённыйКонтекстЗапускаКодекс
    ) throws -> ПланПодтверждённогоЗапускаКодекс {
        let ожидаемый = кандидат.ожидаемыйКонтекст
        let текущий = наблюдённыйКонтекст
        guard буквально(текущий.идентификаторКорневойЗадачи,
                         ожидаемый.идентификаторКорневойЗадачи),
              буквально(текущий.идентификаторЭтапа, ожидаемый.идентификаторЭтапа),
              буквально(текущий.физическийКорень, ожидаемый.физическийКорень),
              буквально(текущий.полныйRef, ожидаемый.полныйRef),
              текущий.исходныйOID == ожидаемый.исходныйOID,
              текущий.исходноеДерево == ожидаемый.исходноеДерево,
              текущий.деревоИндекса == ожидаемый.деревоКоммита,
              текущий.родители == ожидаемый.родители
        else { throw ОтказПодготовкиЗапускаКодекс.изменилось }
        return кандидат.план
    }

    private static func кодировать<T: Encodable>(_ значение: T) throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(значение)
    }

    // Явный профиль: canonical UTF-8 JSON, sorted keys, без LF/пробельного
    // оформления/escape-альтернатив/duplicate keys/неизвестных полей.
    private static func канонический<T: Codable>(
        _ тип: T.Type, _ данные: Data
    ) throws -> T {
        do {
            guard данные.count <= 65_536 else {
                throw ОтказПодготовкиЗапускаКодекс.каноническийJSON
            }
            let объект = try JSONSerialization.jsonObject(with: данные)
            guard объект is [String: Any],
                  try JSONSerialization.data(
                    withJSONObject: объект,
                    options: [.sortedKeys, .withoutEscapingSlashes]) == данные
            else { throw ОтказПодготовкиЗапускаКодекс.каноническийJSON }
            let значение = try JSONDecoder().decode(тип, from: данные)
            guard try кодировать(значение) == данные else {
                throw ОтказПодготовкиЗапускаКодекс.каноническийJSON
            }
            return значение
        } catch {
            throw ОтказПодготовкиЗапускаКодекс.каноническийJSON
        }
    }

    private static func буквально(_ а: String, _ б: String) -> Bool {
        а.utf8.elementsEqual(б.utf8)
    }

    private static func абсолютныйПуть(_ путь: String) -> Bool {
        guard путь.utf8.count <= 4_096, путь.hasPrefix("/"),
              !путь.unicodeScalars.contains(where: CharacterSet.controlCharacters.contains)
        else { return false }
        let части = путь.split(separator: "/", omittingEmptySubsequences: false)
        return части.count > 1 && части.first == ""
            && части.dropFirst().allSatisfy {
                !$0.isEmpty && $0 != "." && $0 != ".."
            }
    }

    private static func полныйRefДействителен(_ значение: String) -> Bool {
        let байты = Array(значение.utf8)
        let запрещённые: Set<UInt8> = [32, 126, 94, 58, 63, 42, 91, 92]
        guard байты.count <= 1_024,
              значение.hasPrefix("refs/heads/"),
              байты.allSatisfy({ $0 > 32 && $0 < 127 && !запрещённые.contains($0) }),
              !значение.contains(".."), !значение.contains("@{"),
              !значение.contains("//")
        else { return false }
        let части = значение.split(separator: "/", omittingEmptySubsequences: false)
        return части.count >= 3 && части.allSatisfy {
            !$0.isEmpty && !$0.hasPrefix(".") && !$0.hasSuffix(".")
                && !$0.hasSuffix(".lock")
        }
    }

    private static func проверитьПины(
        _ пины: [ПинФайлаЗапускаКодекс], ключиДокументов: [String]
    ) throws {
        for пин in пины {
            guard абсолютныйПуть(пин.путь), хэшДействителен(пин.хэш),
                  !ключиДокументов.contains(where: {
                      $0 == пин.путь && !буквально($0, пин.путь)
                  })
            else { throw ОтказПодготовкиЗапускаКодекс.источник }
        }
        for номер in пины.indices {
            for другойНомер in пины.indices where другойНомер > номер {
                let левый = пины[номер]
                let правый = пины[другойНомер]
                if левый.путь == правый.путь && !буквально(левый.путь, правый.путь) {
                    throw ОтказПодготовкиЗапускаКодекс.источник
                }
                if буквально(левый.путь, правый.путь) {
                    guard левый.хэш == правый.хэш else {
                        throw ОтказПодготовкиЗапускаКодекс.источник
                    }
                } else if правый.путь.hasPrefix(левый.путь + "/")
                    || левый.путь.hasPrefix(правый.путь + "/")
                    || правый.путь.utf8.starts(with: Array(левый.путь.utf8) + [47])
                    || левый.путь.utf8.starts(with: Array(правый.путь.utf8) + [47]) {
                    throw ОтказПодготовкиЗапускаКодекс.источник
                }
            }
        }
        for номер in ключиДокументов.indices {
            for другойНомер in ключиДокументов.indices where другойНомер > номер {
                let левый = ключиДокументов[номер]
                let правый = ключиДокументов[другойНомер]
                if левый == правый && !буквально(левый, правый) {
                    throw ОтказПодготовкиЗапускаКодекс.источник
                }
            }
        }
    }

    private static func хэшДействителен(_ значение: String) -> Bool {
        значение.utf8.count == 64 && значение.utf8.allSatisfy {
            (48...57).contains($0) || (97...102).contains($0)
        }
    }

    private static func объект(_ значение: String) -> Bool {
        (значение.utf8.count == 40 || значение.utf8.count == 64)
            && значение.utf8.allSatisfy {
                (48...57).contains($0) || (97...102).contains($0)
            }
    }

    private static func компонентЛичности(_ значение: String) -> Bool {
        !значение.isEmpty && значение.utf8.count <= 2_048
            && значение == значение.trimmingCharacters(in: .whitespacesAndNewlines)
            && !значение.unicodeScalars.contains {
                CharacterSet.controlCharacters.contains($0) || $0 == "<" || $0 == ">"
            }
    }

    private static func датаДействительна(
        _ дата: МоментИдентичностиКоммитаКодекс
    ) -> Bool {
        let байты = Array(дата.смещениеUTC.utf8)
        guard дата.секунды >= 0, байты.count == 5,
              байты[0] == 43 || байты[0] == 45,
              байты.dropFirst().allSatisfy({ (48...57).contains($0) })
        else { return false }
        let часы = Int(байты[1] - 48) * 10 + Int(байты[2] - 48)
        let минуты = Int(байты[3] - 48) * 10 + Int(байты[4] - 48)
        return часы <= 23 && минуты <= 59
    }

    private static func хэш(_ данные: Data) -> String {
        SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
    }

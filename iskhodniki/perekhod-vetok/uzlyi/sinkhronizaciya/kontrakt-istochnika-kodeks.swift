              ожидаемаяИдентичность.идентификаторКорневойЗадачи == этап.идентификаторКорневойЗадачи,
              ожидаемаяИдентичность.идентификаторСнимка == снимок.идентификаторСнимка,
              ожидаемаяИдентичность.хэшСнимка == путь.связывание.хэшСнимка,
              ожидаемаяИдентичность.этап == этап,
              ожидаемаяИдентичность.наблюденоВМиллисекундах == снимок.наблюденоВМиллисекундах,
              путь.имяАвтора == "FUM Codex [\(снимок.модель); effort=\(снимок.усилие)]",
              путь.полныйТекст == сообщение.полныйТекст,
              сообщение.идентификаторКорневойЗадачи == этап.идентификаторКорневойЗадачи,
              сообщение.модель == снимок.модель, сообщение.усилие == снимок.усилие,
              корректноеСообщение(сообщение),
              let пересчитанныйЭтап = try? сформироватьЭтап(

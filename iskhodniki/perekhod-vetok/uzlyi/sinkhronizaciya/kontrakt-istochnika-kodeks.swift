        идентификаторКорневойЗадачи = try контейнер.decode(String.self, forKey: ключДанных("rootUUID"))
        идентификаторЭтапа = try контейнер.decode(String.self, forKey: ключДанных("stageUUID"))
        операция = try контейнер.decode(String.self, forKey: ключДанных("операция"))
        исходнаяСсылка = try контейнер.decode(String.self, forKey: ключДанных("исходныйRef"))
        исходныйИдентификаторОбъекта = try контейнер.decode(String.self, forKey: ключДанных("исходныйOID"))
        исходноеДерево = try контейнер.decode(String.self, forKey: ключДанных("исходноеДерево"))
        входящийИдентификаторОбъекта = try контейнер.decodeIfPresent(String.self, forKey: ключДанных("входящийOID"))
        тема = try контейнер.decode(String.self, forKey: ключДанных("тема"))
        задача = try контейнер.decode(String.self, forKey: ключДанных("задача"))
        изменения = try контейнер.decode(String.self, forKey: ключДанных("изменения"))
        проверки = try контейнер.decode(String.self, forKey: ключДанных("проверки"))
        граница = try контейнер.decode(String.self, forKey: ключДанных("граница"))
    }

    func encode(to кодировщик: Encoder) throws {
        var контейнер = кодировщик.container(keyedBy: КлючДанных.self)
        try контейнер.encode(схема, forKey: ключДанных("схема"))
        try контейнер.encode(идентификаторКорневойЗадачи, forKey: ключДанных("rootUUID"))
        try контейнер.encode(идентификаторЭтапа, forKey: ключДанных("stageUUID"))
        try контейнер.encode(операция, forKey: ключДанных("операция"))
        try контейнер.encode(исходнаяСсылка, forKey: ключДанных("исходныйRef"))
        try контейнер.encode(исходныйИдентификаторОбъекта, forKey: ключДанных("исходныйOID"))
        try контейнер.encode(исходноеДерево, forKey: ключДанных("исходноеДерево"))
        try контейнер.encode(значениеВходящегоИдентификатораОбъекта, forKey: ключДанных("входящийOID"))
        try контейнер.encode(тема, forKey: ключДанных("тема"))

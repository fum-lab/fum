    static func путьСоответствуетЭтапу(
        _ путь: ПроверенныйПутьКодекс, операция: String, исходнаяСсылка: String,
        исходныйИдентификаторОбъекта: String, входящийИдентификаторОбъекта: String?
    ) -> Bool {
        путьДействителен(путь)
            && путь.этап.операция == операция
            && путь.этап.исходнаяСсылка == исходнаяСсылка
            && путь.этап.исходныйИдентификаторОбъекта == исходныйИдентификаторОбъекта
            && путь.этап.входящийИдентификаторОбъекта == входящийИдентификаторОбъекта
    }

    private static func закодироватьСортированно<T: Encodable>(_ значение: T) throws -> Data {
        let кодировщик = JSONEncoder()
        кодировщик.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try кодировщик.encode(значение)
    }

    private static func хэш(_ данные: Data) -> String {
        SHA256.hash(data: данные).map { String(format: "%02x", $0) }.joined()
    }

    private static func действительныйУниверсальныйИдентификатор(_ значение: String) -> Bool {
        UUID(uuidString: значение)?.uuidString.lowercased() == значение
    }

    private static func действительнаяСсылка(_ значение: String) -> Bool {
        значение.hasPrefix("refs/heads/") && !значение.contains("..")
            && !значение.contains("//") && !значение.contains("\\")
            && !значение.unicodeScalars.contains(where: CharacterSet.controlCharacters.contains)
    }

    private static func полныйИдентификаторОбъекта(_ значение: String) -> Bool {
        (значение.count == 40 || значение.count == 64) && значение == значение.lowercased()
            && значение.allSatisfy(\.isHexDigit)
    }

    private static func действительныйТокен(_ значение: String) -> Bool {
        !значение.isEmpty && значение.utf8.count <= 128 && значение.unicodeScalars.allSatisfy {
            $0.value < 128 && (CharacterSet.alphanumerics.contains($0)
                || $0 == "-" || $0 == "." || $0 == "_")
        }
    }

    private static func действительныйНаблюдаемыйТокен(_ значение: String) -> Bool {
        действительныйТокен(значение)
            && !["unknown", "unavailable", "unset", "null"].contains(значение.lowercased())
    }

    private static func корректноеСообщение(_ сообщение: СообщениеКоммитаКодекс) -> Bool {
        [сообщение.тема, сообщение.изменения, сообщение.проверки,
         сообщение.граница, сообщение.модель, сообщение.усилие]
            .allSatisfy(корректноеОднострочноеПоле)
            && корректноеИсходноеТело(сообщение.задача)
            && сообщение.полныйТекст.utf8.count <= ПределыПроверкиПубликации.документ
    }

    private static func корректноеОднострочноеПоле(_ значение: String) -> Bool {
        !значение.isEmpty
            && значение.utf8.count <= 2_048
            && значение.unicodeScalars.contains {
                !CharacterSet.whitespacesAndNewlines.contains($0)
            }
            && !значение.unicodeScalars.contains {
                CharacterSet.controlCharacters.contains($0)
                    || CharacterSet.newlines.contains($0)
            }
    }

    private static func корректноеИсходноеТело(_ значение: String) -> Bool {
        !значение.isEmpty
            && значение.utf8.count <= ПределыПроверкиПубликации.документ
            && значение.unicodeScalars.contains {
                !CharacterSet.whitespacesAndNewlines.contains($0)
            }
            && !значение.unicodeScalars.contains {
                CharacterSet.controlCharacters.contains($0)
                    && $0.value != 9 && $0.value != 10 && $0.value != 13
            }
    }
}


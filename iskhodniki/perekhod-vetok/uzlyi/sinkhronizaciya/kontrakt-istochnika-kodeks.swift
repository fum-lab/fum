    }

    static func выбратьИсточник(
        данныеСнимка: Data, идентификаторСнимка: String, этап: ЭтапСодержимогоКодекс
    ) throws -> Data {
        guard данныеСнимка.count <= ПределыПроверкиПубликации.документ,
              действительныйУниверсальныйИдентификатор(идентификаторСнимка),
              let снимок = try? JSONDecoder().decode(СнимокИдентичностиКодекс.self, from: данныеСнимка),
              снимок.идентификаторСнимка == идентификаторСнимка, снимок.этап == этап
        else { throw ОтказПроверкиПубликации.источникПодменён }
        let выбор = ВыборИсточникаКодекс(
            идентификаторСнимка: идентификаторСнимка,
            хэшСнимка: хэш(данныеСнимка), этап: этап)
        return try закодироватьСортированно(выбор)
    }

    static func проверитьВыбранныйИсточник(
        данныеСнимка: Data?, данныеВыбора: Data?, ожидаемыйЭтап: ЭтапСодержимогоКодекс
    ) throws -> ПроверенноеСвязываниеИсточникаКодекс {
        guard let данныеСнимка, let данныеВыбора else {
            throw ОтказПроверкиПубликации.нетИсточникаЭтапа
        }
        guard данныеСнимка.count <= ПределыПроверкиПубликации.документ,
              данныеВыбора.count <= ПределыПроверкиПубликации.документ,
              let снимок = try? JSONDecoder().decode(СнимокИдентичностиКодекс.self, from: данныеСнимка),
              let выбор = try? JSONDecoder().decode(ВыборИсточникаКодекс.self, from: данныеВыбора)
        else { throw ОтказПроверкиПубликации.источникПодменён }
        guard снимок.схема == СнимокИдентичностиКодекс.схемаДанных,
              снимок.источник == "native-stage-snapshot",
              действительныйУниверсальныйИдентификатор(снимок.этап.идентификаторЭтапа),
              снимок.наблюденоВМиллисекундах > 0,
              снимок.полнота, снимок.неполныйХвост == 0, снимок.пропусков == 0,
              действительныйНаблюдаемыйТокен(снимок.модель), действительныйНаблюдаемыйТокен(снимок.усилие)
        else { throw ОтказПроверкиПубликации.нетИсточникаЭтапа }
        guard снимок.этап == ожидаемыйЭтап,
              выбор.схема == ВыборИсточникаКодекс.схемаДанных,
              выбор.идентификаторСнимка == снимок.идентификаторСнимка,
              действительныйУниверсальныйИдентификатор(выбор.идентификаторСнимка),
              выбор.хэшСнимка == хэш(данныеСнимка),
              выбор.этап == ожидаемыйЭтап
        else { throw ОтказПроверкиПубликации.источникПодменён }
        return ПроверенноеСвязываниеИсточникаКодекс(
            снимок: снимок, этап: ожидаемыйЭтап,
            хэшСнимка: выбор.хэшСнимка)
    }


struct КлючДанных: CodingKey {
    let stringValue: String
    let intValue: Int?

    init?(stringValue: String) {
        self.stringValue = stringValue
        intValue = nil
    }

    init?(intValue: Int) {
        stringValue = String(intValue)
        self.intValue = intValue
    }
}

func ключДанных(_ значение: String) -> КлючДанных { КлючДанных(stringValue: значение)! }

func проверитьЗакрытыйНаборКлючей(
    _ контейнер: KeyedDecodingContainer<КлючДанных>, ожидаемые: Set<String>,
    декодер: Decoder
) throws {
    let фактическиеКлючи = Set(контейнер.allKeys.map(\.stringValue))
    guard фактическиеКлючи == ожидаемые else {
        throw DecodingError.dataCorrupted(.init(
            codingPath: декодер.codingPath,
            debugDescription: "Unexpected or missing field in closed FUM Codex payload."))
    }
}


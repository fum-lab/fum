              действительныйУниверсальныйИдентификатор(снимок.идентификаторСнимка), действительныйУниверсальныйИдентификатор(этап.идентификаторКорневойЗадачи), действительныйУниверсальныйИдентификатор(этап.идентификаторЭтапа),
              снимок.этап == этап, путь.этап == этап,
              снимок.наблюденоВМиллисекундах > 0,
              снимок.полнота, снимок.неполныйХвост == 0, снимок.пропусков == 0,

"""Однократная сборка явно размеченного синтетического снимка; ввода-вывода нет."""
from collections import defaultdict, deque
from datetime import datetime
import hashlib
import json
import re
import uuid
import time

ВЕРСИЯ = 'fum.сборщик-рабочего-контекста.1'
КАТЕГОРИИ = ('цель', 'ограничение', 'решение', 'обязательство', 'зависимость', 'ближайшее-действие')
ПРОИСХОЖДЕНИЯ = ('человек', 'делегирование', 'агент', 'служебное', 'инструмент', 'цитата')
ПРЕДЕЛ_ВХОДА = 8 * 1024 * 1024
ПРЕДЕЛ_СОБЫТИЙ = 4096


def байты(значение):
    return (json.dumps(значение, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False) + '\n').encode('utf-8')


def хэш(сырьё):
    return hashlib.sha256(сырьё).hexdigest()


def уникальный_объект(пары):
    результат = {}
    for ключ, значение in пары:
        if ключ in результат:
            raise ValueError('повторён ключ JSON')
        результат[ключ] = значение
    return результат


def прочитать_джейсон(сырьё):
    try:
        return json.loads(сырьё, object_pairs_hook=уникальный_объект,
                          parse_constant=lambda _: (_ for _ in ()).throw(ValueError('нечисловое значение JSON')))
    except (UnicodeError, RecursionError) as ошибка:
        raise ValueError('некорректный UTF-8 или глубина JSON') from ошибка


def объект(значение, поля):
    if type(значение) is not dict or set(значение) != set(поля.split()):
        raise ValueError('неверные поля контракта')


def строка(значение):
    if type(значение) is not str or not значение.strip():
        raise ValueError('ожидалась непустая строка')
    return значение


def целое(значение, минимум=0):
    if type(значение) is not int or значение < минимум:
        raise ValueError('ожидалось целое число в допустимой области')


def логическое(значение):
    if type(значение) is not bool:
        raise ValueError('ожидалось логическое значение')


def время(значение):
    строка(значение)
    if not re.fullmatch(r'[0-9]{4}-[0-9][0-9]-[0-9][0-9]T[0-9][0-9]:[0-9][0-9]:[0-9][0-9]Z', значение):
        raise ValueError('ожидалось точное UTC-время с секундами')
    return datetime.fromisoformat(значение.replace('Z', '+00:00'))


def ссылки(значение):
    if type(значение) is not list or any(type(пункт) is not str or not пункт.strip() for пункт in значение):
        raise ValueError('неверный список ссылок')
    if len(set(значение)) != len(значение):
        raise ValueError('повторена ссылка')


def проверить_событие(запись):
    if type(запись) is not dict:
        raise ValueError('ожидалось событие')
    общие = 'ид порядок вид происхождение тезис'
    дополнительные = {
        'утверждение': 'категория предмет зависит_от область годность подробности',
        'отмена': 'отменяет', 'приёмка': 'принимает доказательства', 'сообщение': ''}
    if type(запись.get('вид')) is not str or запись['вид'] not in дополнительные:
        raise ValueError('неподдержанный вид события')
    объект(запись, общие + ' ' + дополнительные[запись['вид']])
    строка(запись['ид']); строка(запись['тезис']); целое(запись['порядок'], 1)
    if type(запись['происхождение']) is not str or запись['происхождение'] not in ПРОИСХОЖДЕНИЯ:
        raise ValueError('неподдержанное происхождение')
    if запись['вид'] == 'утверждение':
        if запись['категория'] not in КАТЕГОРИИ:
            raise ValueError('неподдержанная категория')
        строка(запись['предмет']); ссылки(запись['зависит_от'])
        if type(запись['подробности']) is not str:
            raise ValueError('неверные подробности')
        if запись['область'] is not None:
            объект(запись['область'], 'ид версия')
            for значение in запись['область'].values(): строка(значение)
        if запись['годность'] is not None:
            объект(запись['годность'], 'до политика основание')
            время(запись['годность']['до'])
            строка(запись['годность']['политика']); строка(запись['годность']['основание'])
    for поле in ('отменяет', 'принимает', 'доказательства'):
        if поле in запись:
            ссылки(запись[поле])
            if not запись[поле]: raise ValueError('пустое основание перехода')


def разобрать(сырьё):
    if type(сырьё) is not bytes or len(сырьё) > ПРЕДЕЛ_ВХОДА:
        raise ValueError('превышен предел входа или неверный тип байтов')
    вход = прочитать_джейсон(сырьё)
    объект(вход, 'схема задача доставка время_оценки бюджет_байт версии источники')
    if вход['схема'] != 'fum.вход-рабочего-контекста.1':
        raise ValueError('неподдержанная версия входа')
    if str(uuid.UUID(строка(вход['задача']))) != вход['задача']:
        raise ValueError('неканонический UUID задачи')
    объект(вход['доставка'], 'ид подтверждена')
    строка(вход['доставка']['ид']); логическое(вход['доставка']['подтверждена'])
    время(вход['время_оценки']); целое(вход['бюджет_байт'])
    if type(вход['версии']) is not dict:
        raise ValueError('неверная карта версий')
    for ключ, значение in вход['версии'].items(): строка(ключ); строка(значение)
    if type(вход['источники']) is not list or not 1 <= len(вход['источники']) <= 32:
        raise ValueError('ожидалось от одного до 32 источников')
    события, указатели, источники, номера = {}, {}, {}, set()
    for источник in вход['источники']:
        объект(источник, 'ид версия контракт задача доступность полнота байты хэш данные')
        идентификатор = строка(источник['ид'])
        if идентификатор in источники or источник['задача'] != вход['задача']:
            raise ValueError('чужой или повторённый источник')
        строка(источник['контракт']); логическое(источник['полнота'])
        if источник['версия'] is not None: строка(источник['версия'])
        if источник['доступность'] not in ('доступен', 'недоступен'):
            raise ValueError('неверная доступность')
        источники[идентификатор] = источник
        if источник['данные'] is None:
            if (источник['доступность'] != 'недоступен' or источник['полнота'] or
                    источник['байты'] is not None or источник['хэш'] is not None):
                raise ValueError('данные отсутствуют при заявленной доступности')
            continue
        if type(источник['данные']) is not str or источник['версия'] is None:
            raise ValueError('байты требуют версии источника')
        if источник['контракт'] != 'fum.синтетические-события.1':
            raise ValueError('неподдержанный контракт данных источника')
        данные = источник['данные'].encode('utf-8')
        целое(источник['байты'])
        if источник['байты'] != len(данные) or источник['хэш'] != хэш(данные):
            raise ValueError('не совпали хэш или граница байтов источника: ' + идентификатор)
        if данные and not данные.endswith(b'\n'):
            raise ValueError('источник имеет незавершённую строку')
        начало = 0
        for номер, линия in enumerate(данные.splitlines(keepends=True), 1):
            запись = прочитать_джейсон(линия)
            проверить_событие(запись)
            ид = запись['ид']
            if ид in события or запись['порядок'] in номера or len(события) >= ПРЕДЕЛ_СОБЫТИЙ:
                raise ValueError('повторена идентичность/порядок или превышен предел событий')
            события[ид] = запись; номера.add(запись['порядок'])
            указатели[ид] = {'источник': идентификатор, 'версия': источник['версия'],
                            'строка': номер, 'начало': начало, 'конец': начало + len(линия), 'хэш': хэш(линия)}
            начало += len(линия)
    return вход, события, указатели, источники


def собрать(сырьё, метки=None):
    начало = time.perf_counter_ns()
    вход, события, указатели, источники = разобрать(сырьё)
    разбор_завершён = time.perf_counter_ns()
    порядок = sorted(события, key=lambda ид: события[ид]['порядок'])
    причины = {ид: set() for ид in порядок}
    отмены, сомнительные_отмены, конфликты, приёмки = (defaultdict(list) for _ in range(4))
    неполнота = []
    if not вход['доставка']['подтверждена']:
        неполнота.append('граница-доставки-не-подтверждена')
    for ид, источник in источники.items():
        if источник['доступность'] != 'доступен': неполнота.append('источник-недоступен:' + ид)
        if not источник['полнота']: неполнота.append('источник-неполон:' + ид)
    for ид in порядок:
        запись = события[ид]; источник = источники[указатели[ид]['источник']]
        if not вход['доставка']['подтверждена']: причины[ид].add('граница-доставки-не-подтверждена')
        if источник['доступность'] != 'доступен': причины[ид].add('источник-недоступен:' + источник['ид'])
        if not источник['полнота']: причины[ид].add('источник-неполон:' + источник['ид'])
        if запись['вид'] == 'утверждение':
            область = запись['область']
            if область is not None:
                версия = вход['версии'].get(область['ид'])
                if версия is None: причины[ид].add('версия-неизвестна:' + область['ид'])
                elif версия != область['версия']: причины[ид].add('версия-изменилась:' + область['ид'])
            if запись['годность'] and время(вход['время_оценки']) >= время(запись['годность']['до']):
                причины[ид].add('истёк-срок:' + запись['годность']['политика'])
    # Порядок — явный синтетический причинный порядок, а не время получения.
    for ид in порядок:
        запись = события[ид]
        if запись['вид'] != 'отмена': continue
        подтверждена = (запись['происхождение'] == 'человек' and not причины[ид]
                         and all(цель in события for цель in запись['отменяет']))
        if not подтверждена: причины[ид].add('отмена-не-подтверждена')
        for цель in запись['отменяет']:
            if цель not in события:
                причины[ид].add('цель-отмены-отсутствует:' + цель); continue
            if события[цель]['вид'] != 'утверждение' or события[цель]['порядок'] >= запись['порядок']:
                raise ValueError('отмена должна адресовать более раннее утверждение')
            if подтверждена: отмены[цель].append(ид)
            else:
                сомнительные_отмены[цель].append(ид)
                причины[цель].add('неподтверждённая-отмена:' + ид)
    группы = defaultdict(list)
    for ид in порядок:
        запись = события[ид]
        if запись['вид'] == 'утверждение' and not отмены[ид]:
            # Область с версией различает несовпадающие предметы проверок.
            группы[(запись['категория'], запись['предмет'], байты(запись['область']))].append(ид)
    группы_конфликтов = []
    for группа in группы.values():
        if len({события[ид]['тезис'] for ид in группа}) > 1:
            ключ = 'КОНФЛИКТ-' + str(len(группы_конфликтов) + 1)
            группы_конфликтов.append({'ид': ключ, 'участники': группа})
            for ид in группа: конфликты[ид] = ключ
    # Сначала считаем локальные состояния; затем каждый потомок посещается один раз.
    состояния = {}
    for ид in порядок:
        if отмены[ид]: состояния[ид] = 'отменено'
        elif конфликты[ид]: состояния[ид] = 'противоречие'
        elif any(причина.startswith(('истёк-срок:', 'версия-изменилась:')) for причина in причины[ид]): состояния[ид] = 'устарело'
        elif причины[ид]: состояния[ид] = 'неизвестно'
        elif события[ид]['вид'] == 'сообщение': состояния[ид] = 'сообщение'
        else: состояния[ид] = 'актуально'
    потомки, степени = defaultdict(list), {ид: 0 for ид in порядок}
    for ид in порядок:
        запись = события[ид]
        зависимости = запись.get('зависит_от', []) + запись.get('доказательства', [])
        for предок in зависимости:
            if предок not in события:
                причины[ид].add('основание-отсутствует:' + предок)
                if состояния[ид] == 'актуально': состояния[ид] = 'неизвестно'
            else:
                if события[предок]['вид'] != 'утверждение':
                    raise ValueError('основание должно ссылаться на утверждение')
                if запись['вид'] == 'приёмка':
                    if (события[предок]['порядок'] >= запись['порядок'] or
                            события[предок].get('категория') != 'решение'):
                        raise ValueError('приёмка требует отдельное более раннее свидетельство-решение')
                потомки[предок].append(ид); степени[ид] += 1
    очередь = deque(ид for ид in порядок if степени[ид] == 0)
    посещено = 0
    while очередь:
        ид = очередь.popleft(); посещено += 1
        for потомок in потомки[ид]:
            if состояния[ид] != 'актуально':
                причины[потомок].add('основание-неактуально:' + ид)
                if состояния[потомок] == 'актуально': состояния[потомок] = 'устарело'
            степени[потомок] -= 1
            if степени[потомок] == 0: очередь.append(потомок)
    if посещено != len(порядок): raise ValueError('цикл зависимостей не поддержан')
    for ид in порядок:
        запись = события[ид]
        if запись['вид'] != 'приёмка': continue
        допустима = (состояния[ид] == 'актуально' and запись['происхождение'] == 'человек'
                     and all(цель in события for цель in запись['принимает']))
        if not допустима:
            причины[ид].add('приёмка-не-подтверждена'); состояния[ид] = 'неизвестно'
        for цель in запись['принимает']:
            if цель not in события:
                причины[ид].add('цель-приёмки-отсутствует:' + цель); continue
            if (события[цель].get('категория') != 'обязательство' or
                    события[цель]['порядок'] >= запись['порядок']):
                raise ValueError('приёмка должна адресовать более раннее обязательство')
            if допустима and состояния[цель] == 'актуально': приёмки[цель].append(ид)
    записи, незавершённые, ближайшие = [], [], []
    for ид in порядок:
        исходная = события[ид]
        запись = {ключ: значение for ключ, значение in исходная.items() if ключ != 'подробности'}
        запись.update({'состояние': состояния[ид], 'причины': sorted(причины[ид]),
                       'отмены': отмены[ид], 'конфликт': конфликты[ид] or None, 'приёмки': приёмки[ид],
                       'указатель': указатели[ид]})
        if исходная.get('категория') == 'обязательство':
            запись['обязательство'] = 'завершено' if приёмки[ид] else 'отменено' if отмены[ид] else 'открыто'
            if запись['обязательство'] == 'открыто': незавершённые.append(ид)
        if исходная.get('категория') == 'ближайшее-действие' and состояния[ид] == 'актуально': ближайшие.append(ид)
        записи.append(запись)
    результат = {'схема': 'fum.рабочий-контекст.1', 'сборщик': ВЕРСИЯ, 'задача': вход['задача'],
                 'хэш_снимка': хэш(сырьё), 'доставка': вход['доставка'], 'время_оценки': вход['время_оценки'],
                 'версии': вход['версии'], 'бюджет_байт': вход['бюджет_байт'], 'размер_байт': 0,
                 'превышен_бюджет': 0, 'подробности_полны': False, 'полнота_источников': not неполнота,
                 'неполнота': неполнота, 'граница': 'Только принятый синтетический снимок; живое состояние не проверяется.',
                 'источники': [{ключ: значение for ключ, значение in источник.items() if ключ != 'данные'} for источник in вход['источники']],
                 'конфликты': группы_конфликтов, 'записи': записи, 'незавершённые_обязательства': незавершённые, 'ближайшие_действия': ближайшие,
                 'подробности': []}
    вычисление_завершено = time.perf_counter_ns()
    варианты = [{'ид': ид, 'текст': события[ид]['подробности']} for ид in порядок if события[ид].get('подробности')]
    замкнуть_размер(результат)
    # Обязательные сведения никогда не сокращаются. Опциональные детали — префикс.
    постоянная_часть = результат['размер_байт'] - len(str(результат['размер_байт']))
    for номер, вариант in enumerate(варианты):
        добавка = len(байты(вариант)) - 1 + int(номер > 0)
        без_цифр = постоянная_часть + добавка - int(номер == len(варианты)-1)
        оценка = без_цифр + len(str(без_цифр))
        while оценка != без_цифр + len(str(оценка)):
            оценка = без_цифр + len(str(оценка))
        if оценка > вход['бюджет_байт']: break
        результат['подробности'].append(вариант)
        постоянная_часть += добавка
    результат['подробности_полны'] = len(результат['подробности']) == len(варианты)
    замкнуть_размер(результат)
    if метки is not None:
        метки.extend([{'этап': 'разбор', 'наносекунды': разбор_завершён - начало},
                      {'этап': 'вычисление', 'наносекунды': вычисление_завершено - разбор_завершён},
                      {'этап': 'упаковка', 'наносекунды': time.perf_counter_ns() - вычисление_завершено}])
    return результат


def замкнуть_размер(результат):
    while True:
        размер = len(байты(результат))
        превышен = int(размер > результат['бюджет_байт'])
        if размер == результат['размер_байт'] and превышен == результат['превышен_бюджет']: return
        результат['размер_байт'] = размер; результат['превышен_бюджет'] = превышен

import Foundation
import XCTest
@testable import ПоддержкаОтвета

final class ПроверкиОпераций: XCTestCase {
  func test_ОбщаяМатрица() throws {
    let ресурс = try XCTUnwrap(Bundle.module.resourceURL)
    let примеры = try разобратьJSON(Data(contentsOf: ресурс.appendingPathComponent("семантика-операций.json"))).массив()
    let модель: ЗначениеJSON = .объект(["имя": .строка("Пример"), "поля": .массив([.объект([
      "ключ": .строка("é"), "тип": .строка("строка"), "присутствие": .строка("обязательно"),
      "null": .строка("нет"), "варианты": .массив([.строка("é")])])])])
    for пример in примеры {
      let поля = try пример.объект(), имя = try поля["название"]!.строка()
      let описание = ЗначениеJSON.объект(["схема": .строка("fum.структурный-контракт.1"),
        "числа": .строка("целые64-без-дробей"), "модели": .массив([модель]),
        "переменные": .массив([]), "результат": поля["выражение"]!])
      let контракт = try КонтрактМоделей(кодированноеОписание: JSONEncoder().encode(описание).base64EncodedString())
      if поля["отказ"] == .логическое(true) {
        XCTAssertThrowsError(try контракт.спроецировать(поля["вход"]!, артефакт: .объект([:]), ожидаемаяЗадача: ""), имя)
      } else {
        XCTAssertEqual(try контракт.спроецировать(поля["вход"]!, артефакт: .объект([:]), ожидаемаяЗадача: ""), поля["значение"]!, имя)
      }
    }
  }
}

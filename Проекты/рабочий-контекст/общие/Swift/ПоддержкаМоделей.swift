import Foundation

public struct КонтрактМоделей: Sendable {
  private let описание: [String: ЗначениеJSON]
  private let модели: [String: ЗначениеJSON]

  public init(base64: String) throws {
    guard let данные = Data(base64Encoded: base64) else { throw ОшибкаПредставления.отказ("Повреждено описание") }
    let описание = try разобратьJSON(данные).объект()
    try потребовать(описание["схема"] == .строка("fum.структурный-контракт.1") &&
      описание["числа"] == .строка("целые64-без-дробей"), "Неизвестный профиль моделей")
    var модели: [String: ЗначениеJSON] = [:]
    for модель in try описание["модели"]!.массив() {
      let имя = try модель.объект()["имя"]!.строка()
      try потребовать(модели[имя] == nil, "Повтор модели")
      модели[имя] = модель
    }
    self.описание = описание
    self.модели = модели
  }

  public func проверить(_ значение: ЗначениеJSON, модель имя: String) throws {
    guard let модель = модели.точно(имя) else { throw ОшибкаПредставления.отказ("Неизвестная модель") }
    let поля = try модель.объект()["поля"]!.массив().map { try $0.объект() }
    let объект = try значение.объект()
    let допустимые = try Set(поля.map { try Data($0["ключ"]!.строка().utf8) })
    try потребовать(Set(объект.keys.map { Data($0.utf8) }).isSubset(of: допустимые), "Неизвестное поле модели")
    for поле in поля {
      let ключ = try поле["ключ"]!.строка()
      let часть = объект.точно(ключ) ?? .отсутствует
      if часть == .отсутствует {
        try потребовать(поле["присутствие"] == .строка("необязательно"), "Отсутствует обязательное поле")
      } else if часть == .пусто {
        try потребовать(поле["null"] == .строка("да"), "Null не разрешён для поля")
      } else {
        try проверитьТип(поле["тип"]!.строка(), значение: часть)
        let варианты = try поле["варианты"]!.массив()
        try потребовать(варианты.isEmpty || варианты.contains(часть), "Неизвестный вариант поля")
      }
    }
  }

  private func проверитьТип(_ тип: String, значение: ЗначениеJSON) throws {
    switch тип {
    case "строка": _ = try значение.строка()
    case "целое": _ = try значение.целое()
    case "логическое":
      guard case .логическое = значение else { throw ОшибкаПредставления.отказ("Ожидалось логическое значение") }
    case "JSON": try потребовать(значение != .отсутствует, "Отсутствие не является JSON")
    default:
      if тип.hasPrefix("массив<"), тип.hasSuffix(">") {
        for часть in try значение.массив() { try проверитьТип(String(тип.dropFirst(7).dropLast()), значение: часть) }
      } else if тип.hasPrefix("словарь<"), тип.hasSuffix(">") {
        for часть in try значение.объект().values { try проверитьТип(String(тип.dropFirst(8).dropLast()), значение: часть) }
      } else { try проверить(значение, модель: тип) }
    }
  }

  public func спроецировать(_ вход: ЗначениеJSON, артефакт: ЗначениеJSON, ожидаемаяЗадача: String) throws -> ЗначениеJSON {
    var среда: [String: ЗначениеJSON] = ["вход": вход, "артефакт": артефакт, "ожидаемаяЗадача": .строка(ожидаемаяЗадача)]
    func вычислить(_ узел: ЗначениеJSON) throws -> ЗначениеJSON {
      if case .объект(let поля) = узел {
        var результат: [String: ЗначениеJSON] = [:]
        for ключ in поля.keys.sorted() {
          let значение = try вычислить(поля[ключ]!)
          if значение != .отсутствует { результат[ключ] = значение }
        }
        return .объект(результат)
      }
      guard case .массив(let части) = узел else { return узел }
      guard let первая = части.first else { throw ОшибкаПредставления.отказ("Нет операции") }
      let операция = try первая.строка()
      if операция == "переменная" {
        guard let значение = среда[try части[1].строка()] else { throw ОшибкаПредставления.отказ("Нет переменной") }
        return значение
      }
      if операция == "если" {
        guard case .логическое(let условие) = try вычислить(части[1]) else {
          throw ОшибкаПредставления.отказ("Условие не является логическим")
        }
        return try вычислить(части[условие ? 2 : 3])
      }
      let аргументы = try части.dropFirst().map(вычислить)
      switch операция {
      case "null": return .пусто
      case "истина": return .логическое(true)
      case "ложь": return .логическое(false)
      case "массив": return .массив(аргументы)
      case "путь":
        var значение = аргументы[0]
        for часть in аргументы.dropFirst() {
          if !значение.есть { return значение }
          switch значение {
          case .объект(let поля): значение = поля.точно(try часть.строка()) ?? .отсутствует
          case .массив(let элементы):
            let номер = try часть.целое()
            try потребовать(номер >= 0 && номер < элементы.count, "Индекс вне массива")
            значение = элементы[Int(номер)]
          default: throw ОшибкаПредставления.отказ("Путь не соответствует структуре")
          }
        }
        return значение
      case "первый": return try аргументы[0].массив().first ?? .пусто
      case "без-полей":
        if аргументы[0] == .пусто { return .пусто }
        let исключённые = try Set(аргументы[1].массив().map { try Data($0.строка().utf8) })
        return .объект(try аргументы[0].объект().filter { !исключённые.contains(Data($0.key.utf8)) })
      case "равно": return .логическое(аргументы[0] == аргументы[1])
      case "не-null": return .логическое(аргументы[0].есть)
      case "длина":
        let число: Int
        switch аргументы[0] {
        case .массив(let элементы): число = элементы.count
        case .объект(let поля): число = поля.count
        case .строка(let строка): число = строка.unicodeScalars.count
        default: throw ОшибкаПредставления.отказ("Нет длины у значения")
        }
        return .целое(Int64(число))
      case "вычесть":
        let (результат, переполнение) = try аргументы[0].целое().subtractingReportingOverflow(аргументы[1].целое())
        try потребовать(!переполнение, "Переполнение разности")
        return .целое(результат)
      case "потребовать-равно":
        try потребовать(аргументы[0] == аргументы[1], "Не совпало обязательное значение")
        return .логическое(true)
      case "потребовать-ложь-или-отсутствие":
        try потребовать(аргументы[0] == .логическое(false) || аргументы[0] == .отсутствует, "Оболочка сообщает ошибку")
        return .логическое(true)
      case "потребовать-положительное":
        try потребовать(аргументы[0].целое() > 0, "Нужно положительное целое")
        return .логическое(true)
      case "разобрать-JSON":
        let значение = try разобратьJSON(Data(аргументы[0].строка().utf8))
        try проверить(значение, модель: аргументы[1].строка())
        return значение
      case "собрать-вложенные":
        let поле = try аргументы[1].строка()
        return .массив(try аргументы[0].массив().flatMap { родитель in
          guard let значение = try родитель.объект().точно(поле) else { throw ОшибкаПредставления.отказ("Нет вложенного поля") }
          return try значение.массив()
        })
      case "проверить-варианты":
        let поле = try аргументы[1].строка(), варианты = try аргументы[2].объект()
        for элемент in try аргументы[0].массив() {
          guard let тип = try элемент.объект().точно(поле), let модель = варианты.точно(try тип.строка()) else {
            throw ОшибкаПредставления.отказ("Неизвестный вариант элемента")
          }
          if модель != .строка("JSON") { try проверить(элемент, модель: модель.строка()) }
        }
        return .логическое(true)
      case "выбрать-вложенный":
        let родители = try аргументы[0].массив(), поле = try аргументы[1].строка()
        let дискриминатор = try аргументы[2].строка(), вариант = аргументы[3], текст = try аргументы[4].строка()
        let пробелы = try Set(аргументы[5].массив().map { try $0.целое() })
        var выбранный = ЗначениеJSON.пусто
        for (номерРодителя, родитель) in родители.enumerated() {
          guard let значение = try родитель.объект().точно(поле) else { throw ОшибкаПредставления.отказ("Нет вложенных элементов") }
          var последний = ЗначениеJSON.пусто
          for (номер, элемент) in try значение.массив().enumerated() {
            let поля = try элемент.объект()
            guard let тип = поля.точно(дискриминатор) else { throw ОшибкаПредставления.отказ("Нет дискриминатора") }
            if тип == вариант {
              guard let содержание = поля.точно(текст) else { throw ОшибкаПредставления.отказ("Нет текста кандидата") }
              if try содержание.строка().unicodeScalars.contains(where: { !пробелы.contains(Int64($0.value)) }) {
                последний = .объект(["значение": элемент, "родитель": родитель,
                  "номерРодителя": .целое(Int64(номерРодителя)), "номер": .целое(Int64(номер))])
              }
            }
          }
          if выбранный == .пусто, последний != .пусто { выбранный = последний }
        }
        return выбранный
      case "группировать":
        let поле = try аргументы[1].строка()
        var счётчики: [String: Int64] = [:]
        for элемент in try аргументы[0].массив() {
          guard let значение = try элемент.объект().точно(поле) else { throw ОшибкаПредставления.отказ("Нет поля группировки") }
          let ключ = try значение.строка()
          try потребовать(счётчики[ключ] == nil || счётчики.точно(ключ) != nil,
            "Канонически совпадающие ключи группировки")
          let (число, переполнение) = (счётчики.точно(ключ) ?? 0).addingReportingOverflow(1)
          try потребовать(!переполнение, "Переполнение счётчика")
          счётчики[ключ] = число
        }
        return .объект(счётчики.mapValues { .целое($0) })
      case "убрать-выбранный":
        var счётчики = try аргументы[0].объект()
        for число in счётчики.values { _ = try число.целое() }
        if аргументы[1].есть {
          let ключ = try аргументы[1].строка()
          guard let число = счётчики.точно(ключ) else { throw ОшибкаПредставления.отказ("Нет выбранного в счётчике") }
          let (разность, переполнение) = try число.целое().subtractingReportingOverflow(1)
          try потребовать(!переполнение, "Переполнение разности счётчика")
          счётчики[ключ] = .целое(разность)
        }
        return .объект(счётчики.filter { $0.value != .целое(0) })
      case "считать-не-null":
        let поле = try аргументы[1].строка()
        var число: Int64 = 0
        for элемент in try аргументы[0].массив() {
          guard let значение = try элемент.объект().точно(поле) else { throw ОшибкаПредставления.отказ("Нет считаемого поля") }
          if значение != .пусто { число += 1 }
        }
        return .целое(число)
      case "указатель":
        let сегменты = try аргументы[0].массив().map { часть -> String in
          let строка: String
          switch часть {
          case .строка(let значение): строка = значение
          case .целое(let значение): строка = String(значение)
          default: throw ОшибкаПредставления.отказ("Неверный сегмент указателя")
          }
          return строка.replacingOccurrences(of: "\u{007E}", with: "\u{007E}0").replacingOccurrences(of: "/", with: "\u{007E}1")
        }
        return .строка(([""] + сегменты).joined(separator: "/"))
      default: throw ОшибкаПредставления.отказ("Неизвестная операция проекции")
      }
    }
    for запись in try описание["переменные"]!.массив() {
      let поля = try запись.объект()
      среда[try поля["имя"]!.строка()] = try вычислить(поля["значение"]!)
    }
    return try вычислить(описание["результат"]!)
  }
}

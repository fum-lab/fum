import Foundation
import CoreFoundation

struct КонтекстГостевыхИзмерений: Codable, Equatable {
    var машина: String
    var план: String
    var проверка: String
    var исходник: String
    var родитель: String
}

struct ФайлГостевогоИзмерения: Codable, Equatable {
    var имя: String
    var контрольнаяСумма: String
    var данные: String
    enum CodingKeys: String, CodingKey {
        case имя, данные
        case контрольнаяСумма = "sha256"
    }
}

struct СводкаГостевыхИзмерений {
    let файлы: [ФайлГостевогоИзмерения]
    let события: [СобытиеМашины]
    let завершённых: Int
    fileprivate let внешнийРодитель: String
    func подтвердитьПрофиль() throws {
        guard [38, 43].contains(события.count), завершённых == события.count,
              события.allSatisfy({ $0.исход == "успех" && $0.длительностьНс != nil }),
              let корень = события.first(where: { $0.родитель == внешнийРодитель }) else {
            throw ОшибкаМашины("Для готовности нужны все успешные пары гостевого профиля.")
        }
        let дети = Dictionary(grouping: события, by: { $0.родитель ?? "" })
        func состав(_ номер: String) -> [String: Int] {
            Dictionary(grouping: дети[номер] ?? [], by: \.операция).mapValues(\.count)
        }
        let верхний: [String: Int] = ["Завершение cloud-init": 1, "Файловая система гостя": 1, "Гостевой DNS": 1,
            "HTTPS через ограниченный хостовый туннель": 1, "Версия Git": 1,
            "Подготовка точного гостевого клона": 1, "Переносимый профиль FUM": 1]
        guard состав(корень.идентификатор) == верхний,
              let клон = дети[корень.идентификатор]?.first(where: { $0.операция == "Подготовка точного гостевого клона" }),
              let профиль = дети[корень.идентификатор]?.first(where: { $0.операция == "Переносимый профиль FUM" }) else {
            throw ОшибкаМашины("Состав верхнего уровня гостевого профиля изменён.")
        }
        let команды = ["Git: for-each-ref": 1, "Git: config": 1, "Git: remote": 2,
            "Git: rev-parse": 5, "Git: ls-tree": 1, "Git: ls-files": 2]
        var первичный = команды
        for имя in ["init", "remote", "fetch", "cat-file", "checkout"] { первичный["Git: " + имя, default: 0] += 1 }
        var переносимый = команды
        for имя in ["fum-proyektnyiye-fajlyi", "fum-moskovskoye-vremya-rabochej-sessii", "fum-indeks-readme", "fum-obratnyiye-ssyilki-voprosov"] {
            переносимый["Набор " + имя] = 1
        }
        for имя in ["fum-indeks-readme", "fum-obratnyiye-ssyilki-voprosov"] { переносимый["Индекс " + имя] = 1 }
        guard состав(клон.идентификатор) == (события.count == 43 ? первичный : команды),
              состав(профиль.идентификатор) == переносимый else {
            throw ОшибкаМашины("Гостевой профиль не содержит точные команды клона, наборов и индексов.")
        }
        let ветви = Set([корень.идентификатор, клон.идентификатор, профиль.идентификатор])
        guard события.allSatisfy({ ветви.contains($0.идентификатор) || дети[$0.идентификатор] == nil }) else {
            throw ОшибкаМашины("Лист гостевого профиля содержит неожиданные дочерние события.")
        }
    }
}

enum ИмпортГостевыхИзмерений {
    private struct Фаза {
        var файл: ФайлГостевогоИзмерения
        var событие: СобытиеМашины
        var начало: Bool
    }
    private static func идентичность(_ строка: String) -> Bool {
        UUID(uuidString: строка)?.uuidString.lowercased() == строка
    }
    private static func отпечаток(_ строка: String) -> Bool {
        строка.utf8.count == 64 && строка.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
    private static func объект(_ байты: Data, ключи: Set<String>) throws -> [String: Any] {
        guard let объект = try JSONSerialization.jsonObject(with: байты) as? [String: Any],
              Set(объект.keys) == ключи else { throw ОшибкаМашины("Неизвестная схема гостевого измерения.") }
        return объект
    }
    private static func разобрать(_ файл: ФайлГостевогоИзмерения, контекст: КонтекстГостевыхИзмерений) throws -> Фаза {
        let байты = Data(файл.данные.utf8)
        guard байты.count <= 64 * 1024, отпечаток(файл.контрольнаяСумма), хэш(байты) == файл.контрольнаяСумма else {
            throw ОшибкаМашины("Байты гостевого измерения не совпадают с отпечатком.")
        }
        let тело = try объект(байты, ключи: ["идентификатор", "родитель", "операция", "исход", "длительностьНс", "происхождение", "запуск"])
        guard let номер = тело["идентификатор"] as? String, идентичность(номер), номер != контекст.родитель,
              let родитель = тело["родитель"] as? String, идентичность(родитель), родитель != номер,
              let операция = тело["операция"] as? String, !операция.isEmpty, операция.utf8.count <= 1024,
              let исход = тело["исход"] as? String,
              тело["происхождение"] as? String == контекст.исходник,
              тело["запуск"] as? String == контекст.проверка else {
            throw ОшибкаМашины("Гостевое событие имеет чужое происхождение или неверную идентичность.")
        }
        let начало = файл.имя == "начало-" + номер + ".json"
        guard начало || файл.имя == "конец-" + номер + ".json" else {
            throw ОшибкаМашины("Имя файла не соответствует фазе и UUID измерения.")
        }
        let длительность: UInt64?
        if начало {
            guard исход == "выполняется", тело["длительностьНс"] is NSNull else {
                throw ОшибкаМашины("Начало измерения не может содержать итог.")
            }
            длительность = nil
        } else {
            guard ["успех", "ошибка"].contains(исход), let число = тело["длительностьНс"] as? NSNumber,
                  CFGetTypeID(число) != CFBooleanGetTypeID(), let значение = UInt64(число.stringValue) else {
                throw ОшибкаМашины("Конец измерения требует исхода и целой неотрицательной длительности.")
            }
            длительность = значение
        }
        return Фаза(файл: файл, событие: СобытиеМашины(идентификатор: номер, родитель: родитель,
            операция: операция, длительностьНс: длительность, исход: исход), начало: начало)
    }
    static func свести(_ пакеты: [Data], контекст: КонтекстГостевыхИзмерений) throws -> СводкаГостевыхИзмерений {
        guard идентичность(контекст.машина), идентичность(контекст.проверка), идентичность(контекст.родитель),
              отпечаток(контекст.план), отпечаток(контекст.исходник), пакеты.count <= 64 else {
            throw ОшибкаМашины("Неверный контекст импорта гостевых измерений.")
        }
        var фазы: [String: Фаза] = [:]
        var объём = 0
        for пакет in пакеты {
            guard пакет.count <= 4 * 1024 * 1024 else { throw ОшибкаМашины("Пакет гостевых измерений слишком велик.") }
            let тело = try объект(пакет, ключи: ["схема", "машина", "план", "проверка", "исходник", "файлы"])
            guard тело["схема"] as? String == "fum.измерения-гостя.1", тело["машина"] as? String == контекст.машина,
                  тело["план"] as? String == контекст.план, тело["проверка"] as? String == контекст.проверка,
                  тело["исходник"] as? String == контекст.исходник, let файлы = тело["файлы"] as? [[String: Any]],
                  файлы.count <= 16_384 else { throw ОшибкаМашины("Пакет относится к другой проверке гостя.") }
            for запись in файлы {
                guard Set(запись.keys) == ["имя", "sha256", "данные"], let имя = запись["имя"] as? String,
                      let сумма = запись["sha256"] as? String, let данные = запись["данные"] as? String else {
                    throw ОшибкаМашины("Неизвестная схема файла гостевого измерения.")
                }
                let файл = ФайлГостевогоИзмерения(имя: имя, контрольнаяСумма: сумма, данные: данные)
                if let прежняя = фазы[имя] {
                    guard прежняя.файл.контрольнаяСумма == сумма,
                          Data(прежняя.файл.данные.utf8) == Data(данные.utf8) else {
                        throw ОшибкаМашины("Повтор фазы изменил прежние байты.")
                    }
                    continue
                }
                объём += данные.utf8.count
                guard объём <= 4 * 1024 * 1024, фазы.count < 16_384 else {
                    throw ОшибкаМашины("Объединённые гостевые измерения слишком велики.")
                }
                фазы[имя] = try разобрать(файл, контекст: контекст)
            }
        }
        var события: [String: СобытиеМашины] = [:]
        var завершённых = 0
        for (_, пара) in Dictionary(grouping: фазы.values, by: { $0.событие.идентификатор }) {
            var событие = пара[0].событие
            if пара.count == 2 {
                guard let начало = пара.first(where: { $0.начало }), let конец = пара.first(where: { !$0.начало }),
                      начало.событие.родитель == конец.событие.родитель,
                      Data(начало.событие.операция.utf8) == Data(конец.событие.операция.utf8) else {
                    throw ОшибкаМашины("Метаданные начала и конца измерения различаются.")
                }
                событие = конец.событие
                завершённых += 1
            } else {
                событие.длительностьНс = nil
                событие.исход = "неполное свидетельство"
            }
            события[событие.идентификатор] = событие
        }
        // Сначала собраны все пакеты: конец и потомок могут прийти раньше начала и родителя.
        var проверенные: Set<String> = []
        for событие in события.values {
            var цепочка: Set<String> = []
            var текущий = событие
            while !проверенные.contains(текущий.идентификатор) {
                guard цепочка.insert(текущий.идентификатор).inserted else { throw ОшибкаМашины("В измерениях найден цикл родителей.") }
                if текущий.родитель == контекст.родитель {
                    guard текущий.операция == "Готовность Linux" else { throw ОшибкаМашины("Неизвестный корень гостевых измерений.") }
                    break
                }
                guard let родитель = текущий.родитель, let следующий = события[родитель] else {
                    throw ОшибкаМашины("Родитель гостевого события отсутствует в выбранном запуске.")
                }
                текущий = следующий
            }
            проверенные.formUnion(цепочка)
        }
        guard события.values.filter({ $0.родитель == контекст.родитель }).count <= 1 else {
            throw ОшибкаМашины("В одном запуске найдено несколько корней гостевых измерений.")
        }
        return СводкаГостевыхИзмерений(файлы: фазы.values.map(\.файл).sorted { $0.имя < $1.имя },
            события: события.values.sorted { $0.идентификатор < $1.идентификатор }, завершённых: завершённых,
            внешнийРодитель: контекст.родитель)
    }
}

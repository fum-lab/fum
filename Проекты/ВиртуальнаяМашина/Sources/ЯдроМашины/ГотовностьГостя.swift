import Foundation

private struct СчётчикиГостя: Decodable {
    var выполнено: Int
    var ошибки: Int
    var отказы: Int
    var пропущено: Int
    var ожидаемые_ошибки: Int
    var неожиданные_успехи: Int
    func проверить(_ число: Int) throws {
        guard выполнено == число, ошибки == 0, отказы == 0, пропущено == 0,
              ожидаемые_ошибки == 0, неожиданные_успехи == 0 else { throw ОшибкаМашины("Гостевой набор неполон.") }
    }
}
private struct НаборГостя: Decodable { var набор: String; var счётчики: СчётчикиГостя }
private struct ПрофильГостя: Decodable {
    var профиль: String; var тесты: Int; var проверки_индексов: Int; var наборы: [НаборГостя]
}
private struct СвидетельствоГостя: Decodable {
    var схема: String; var машина: String; var план: String; var запуск: String; var проверка: String
    var гостевой_запуск: String; var коммит: String; var дерево: String; var инициализация: String
    var файловая_система: String; var сохранённые_данные: String; var профиль: ПрофильГостя
}

public enum ГотовностьГостя {
    public static func проверитьСохранность(_ данные: Data, эталон: Data) throws {
        let новый = try JSONDecoder().decode(СвидетельствоГостя.self, from: данные)
        let прежний = try JSONDecoder().decode(СвидетельствоГостя.self, from: эталон)
        guard новый.машина == прежний.машина, новый.план == прежний.план,
              новый.сохранённые_данные == прежний.сохранённые_данные else {
            throw ОшибкаМашины("Данные прежней VM утрачены или изменены; новый эталон не принимается.")
        }
    }
    public static func проверитьСвидетельство(_ данные: Data, машина: String, план: String, запуск: String, проверка: String) throws {
        let ответ = try JSONDecoder().decode(СвидетельствоГостя.self, from: данные)
        guard ответ.схема == "fum.готовность-гостя.1", ответ.машина == машина, ответ.план == план,
              ответ.запуск == запуск, ответ.проверка == проверка, UUID(uuidString: ответ.гостевой_запуск) != nil,
              ответ.коммит == Профиль().коммит, ответ.дерево == "03e9f37be0717b35e9e87a46fe27e540cd071d63",
              ответ.инициализация == "done", ответ.файловая_система == "ext4",
              ответ.сохранённые_данные.count == 64, ответ.сохранённые_данные.allSatisfy({ "0123456789abcdef".contains($0) }),
              ответ.профиль.профиль == "fum.linux-portable.1", ответ.профиль.тесты == 58,
              ответ.профиль.проверки_индексов == 2, ответ.профиль.наборы.count == 4 else {
            throw ОшибкаМашины("Гостевое свидетельство не подтверждает текущий запуск и полный профиль.")
        }
        let имена = ["fum-proyektnyiye-fajlyi", "fum-moskovskoye-vremya-rabochej-sessii", "fum-indeks-readme", "fum-obratnyiye-ssyilki-voprosov"]
        for (индекс, набор) in ответ.профиль.наборы.enumerated() {
            guard набор.набор == имена[индекс] else { throw ОшибкаМашины("Неизвестный гостевой набор.") }
            try набор.счётчики.проверить([8, 4, 25, 21][индекс])
        }
    }
    public static func выполнить(_ хранилище: Хранилище, _ запуск: ЗапускМашины) throws -> Data {
        let метрики = МетрикиМашины(хранилище)
        let эталон = try хранилище.есть("готовность.json") ? хранилище.прочитать("готовность.json") : nil
        let ожидаемыеДанные = try эталон.map { try JSONDecoder().decode(СвидетельствоГостя.self, from: $0).сохранённые_данные } ?? ""
        return try метрики.измерить("SSH и ограниченный профиль гостя") {
            func отправить(_ вход: Data, _ черезХост: Bool) throws -> РезультатПроцесса {
                let аргументы = try ДоступКГостю.аргументы(каталог: хранилище.путь,
                    порт: запуск.портДоступаКГостю, черезХост: черезХост)
                return try Исполнитель.выполнить("/usr/bin/ssh", аргументы + ["fum", "/usr/bin/python3 -B -s -"],
                    предел: черезХост ? 1100 : 60, вход: вход)
            }
            _ = try ОбменГотовностьюГостя.восстановить(хранилище, отправить: отправить)
            let манифест = try МанифестГотовностиГостя.создать(запуск: запуск,
                родитель: метрики.текущийРодитель!, проверка: UUID().uuidString.lowercased(),
                коммит: хранилище.паспорт.план.профиль.коммит, ожидаемыеДанные: ожидаемыеДанные,
                исходник: РесурсыГостя.текст("готовность.py"), счётчик: РесурсыГостя.текст("проверить-набор.py"),
                наблюдатель: РесурсыГостя.текст("наблюдатель.py"), родительНаблюдателя: РесурсыГостя.текст("родитель_наблюдателя.py"))
            let ответ = try ОбменГотовностьюГостя.выполнить(манифест, хранилище: хранилище, отправить: отправить)
            if let эталон { try проверитьСохранность(ответ, эталон: эталон) }
            return ответ
        }
    }
}

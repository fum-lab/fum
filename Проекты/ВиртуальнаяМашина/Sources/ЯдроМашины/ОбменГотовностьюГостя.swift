import Foundation
import CoreFoundation

struct ВозобновлённыеИзмерения {
    let проверка: String
    let состояние: String
}

enum ОбменГотовностьюГостя {
    private static func байты(_ результат: РезультатПроцесса, операция: String) throws -> Data {
        guard результат.код == 0 else {
            throw ОшибкаМашины("\(операция): код \(результат.код), \(результат.ошибки.suffix(4000))")
        }
        let данные = Data(результат.вывод.utf8)
        guard данные.count <= 4 * 1024 * 1024 else { throw ОшибкаМашины("Ответ гостя превышает 4 MiB.") }
        return данные
    }
    private static func завершена(_ сводка: СводкаГостевыхИзмерений) -> Bool {
        !сводка.события.isEmpty && сводка.завершённых == сводка.события.count
    }
    private static func записатьСостояние(_ манифест: МанифестГотовностиГостя, _ хранилище: Хранилище,
                                         состояние: String, причина: String) throws {
        let имя = "повтор-импорта-" + манифест.контекст.проверка + ".json"
        let байты = try кодировать(["схема": "fum.состояние-импорта.1", "проверка": манифест.контекст.проверка,
            "исходник": манифест.контекст.исходник, "состояние": состояние, "причина": String(причина.suffix(4000))])
        if try хранилище.есть(имя), try хранилище.прочитать(имя) == байты { return }
        try хранилище.записать(имя, байты: байты)
    }
    private static func подтвердитьКонцы(_ ответ: Data, _ сводка: СводкаГостевыхИзмерений) throws {
        guard let тело = try JSONSerialization.jsonObject(with: ответ) as? [String: Any],
              let события = тело["события"] as? [[String: Any]] else {
            throw ОшибкаМашины("Свидетельство готовности не содержит конечные фазы.")
        }
        let концы = сводка.файлы.filter { $0.имя.hasPrefix("конец-") }
        guard события.count == концы.count else { throw ОшибкаМашины("Свидетельство и экспорт содержат разный состав фаз.") }
        var ожидаемые: [String: Data] = [:]
        for файл in концы {
            let событие = try JSONSerialization.jsonObject(with: Data(файл.данные.utf8)) as! [String: Any]
            ожидаемые[событие["идентификатор"] as! String] = try JSONSerialization.data(withJSONObject: событие, options: [.sortedKeys])
        }
        var принятые: Set<String> = []
        let ключи: Set<String> = ["идентификатор", "родитель", "операция", "исход", "длительностьНс", "происхождение", "запуск"]
        for событие in события {
            guard Set(событие.keys) == ключи, let номер = событие["идентификатор"] as? String,
                  принятые.insert(номер).inserted, let число = событие["длительностьНс"] as? NSNumber,
                  CFGetTypeID(число) != CFBooleanGetTypeID(), UInt64(число.stringValue) != nil,
                  try JSONSerialization.data(withJSONObject: событие, options: [.sortedKeys]) == ожидаемые[номер] else {
                throw ОшибкаМашины("Конечные фазы свидетельства отличаются от проверенного экспорта.")
            }
        }
    }
    static func выполнить(_ манифест: МанифестГотовностиГостя, хранилище: Хранилище,
                          отправить: (Data, Bool) throws -> РезультатПроцесса) throws -> Data {
        guard манифест.схема == "fum.манифест-готовности.2" else {
            throw ОшибкаМашины("Прежний манифест разрешает только экспорт; новой готовности нужен v2 и новый UUID.")
        }
        try манифест.сохранить(хранилище)
        let первичный = Result<Data, Error> {
            let ответ = try байты(отправить(манифест.вход, true), операция: "Готовность гостя")
            let тело = try JSONDecoder().decode([String: String].self, from: манифест.данные)
            try ГотовностьГостя.проверитьСвидетельство(ответ, машина: манифест.контекст.машина,
                план: манифест.контекст.план, запуск: тело["запуск"]!, проверка: манифест.контекст.проверка)
            return ответ
        }
        // Экспорт нужен и при исключении основного транспорта; он не выполняет готовность ещё раз.
        let импорт = Result<СводкаГостевыхИзмерений, Error> {
            let пакет = try байты(отправить(манифест.входЭкспорта(), false), операция: "Экспорт измерений гостя")
            return try СохранениеГостевыхИзмерений.принять(пакет, манифест: манифест, хранилище: хранилище)
        }
        do {
            let ответ = try первичный.get()
            let сводка = try импорт.get()
            try сводка.подтвердитьПрофиль()
            try подтвердитьКонцы(ответ, сводка)
            if try хранилище.есть("повтор-импорта-" + манифест.контекст.проверка + ".json") {
                try записатьСостояние(манифест, хранилище, состояние: "завершено", причина: "")
            }
            return ответ
        } catch {
            // Сохранённый запрос остаётся основанием повтора даже при отказе записи диагностики.
            try? записатьСостояние(манифест, хранилище, состояние: "ожидает экспорта", причина: String(describing: ошибкаПервичного(первичный, иначе: error)))
            throw ошибкаПервичного(первичный, иначе: error)
        }
    }
    private static func ошибкаПервичного(_ результат: Result<Data, Error>, иначе: Error) -> Error {
        if case .failure(let ошибка) = результат { return ошибка }
        return иначе
    }
    static func восстановить(_ хранилище: Хранилище,
                             отправить: (Data, Bool) throws -> РезультатПроцесса) throws -> [ВозобновлённыеИзмерения] {
        var итоги: [ВозобновлённыеИзмерения] = []
        for имя in try хранилище.именаАртефактов() where имя.hasPrefix("запрос-готовности-") && имя.hasSuffix(".json") {
            let исходные = try хранилище.прочитать(имя)
            let манифест = try JSONDecoder().decode(МанифестГотовностиГостя.self, from: исходные)
            try манифест.проверитьХранилище(хранилище)
            guard имя == манифест.имя, try кодировать(манифест) == исходные else {
                throw ОшибкаМашины("Архив содержит неканонический сохранённый запрос.")
            }
            var состояние = "ожидает экспорта"
            do {
                let история = "измерения-гостя-" + манифест.контекст.проверка + ".json"
                if try хранилище.есть(история),
                   завершена(try ИмпортГостевыхИзмерений.свести([хранилище.прочитать(история)], контекст: манифест.контекст)) {
                    состояние = "завершено"
                } else {
                    let пакет = try байты(отправить(манифест.входЭкспорта(), false), операция: "Повтор экспорта гостя")
                    let сводка = try СохранениеГостевыхИзмерений.принять(пакет, манифест: манифест, хранилище: хранилище)
                    состояние = завершена(сводка) ? "завершено" : "неполное свидетельство"
                }
                if try состояние != "завершено" || хранилище.есть("повтор-импорта-" + манифест.контекст.проверка + ".json") {
                    try записатьСостояние(манифест, хранилище, состояние: состояние, причина: "")
                }
            } catch {
                try? записатьСостояние(манифест, хранилище, состояние: состояние, причина: String(describing: error))
            }
            итоги.append(ВозобновлённыеИзмерения(проверка: манифест.контекст.проверка, состояние: состояние))
        }
        return итоги
    }
}

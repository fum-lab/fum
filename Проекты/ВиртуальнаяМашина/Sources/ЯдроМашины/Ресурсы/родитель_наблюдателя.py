"""Родитель одной команды: exec точного ресурса не требует __file__.

Публичный API — исполнить_под_наблюдением; все аргументы именованные.
Каталог и уже захваченный flock принадлежат вызывающему, не закрываются
и не разблокируются. Payload, stdin и квитанции сохраняются только в личном
runtime-каталоге. Каждая попытка получает новый UUID без перезаписи старого.
Python macOS >= 3.13, Linux >= 3.12; обязательна capability waitid/WNOWAIT.

Исходник наблюдателя <= 256 KiB, config <= 64 KiB, манифест <= 1 MiB,
stdin и каждый выход <= 32 MiB; срок 1 ns..24 h включает подготовку файлов.
Код 0 наблюдателя удостоверяет только квитанцию: исход команды возвращается
отдельно. Неочищенная группа/непрерываемый ввод-вывод могут удерживать wait
и flock без результата. Наблюдатель и исторические PID не получают сигналов.
При исключении закрывается liveness writer, затем ожидается cleanup.
"""
import fcntl
import hashlib
import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import time
import uuid


def _наблюдение_кодировать(данные):
    return (json.dumps(данные, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False) + '\n').encode()


def _наблюдение_целое(число, нижняя, верхняя):
    return type(число) is int and нижняя <= число <= верхняя


def _наблюдение_файл(номер):
    сведения = os.fstat(номер)
    if (not stat.S_ISREG(сведения.st_mode) or сведения.st_uid != os.getuid()
            or сведения.st_nlink != 1 or сведения.st_mode & 0o077):
        raise ValueError('Нужен личный обычный файл без ссылок')
    return сведения


def _наблюдение_проверить_владение(каталог, замок):
    if not all(type(номер) is int and номер >= 3 for номер in (каталог, замок)) or каталог == замок:
        raise ValueError('Нужны различные дескрипторы каталога и замка')
    сведения = os.fstat(каталог)
    if not stat.S_ISDIR(сведения.st_mode) or сведения.st_uid != os.getuid() or сведения.st_mode & 0o077:
        raise ValueError('Каталог наблюдения должен быть личным')
    свой = _наблюдение_файл(замок)
    иной = os.open('замок', os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=каталог)
    try:
        проверка = _наблюдение_файл(иной)
        if (свой.st_dev, свой.st_ino) != (проверка.st_dev, проверка.st_ino):
            raise ValueError('Дескриптор замка не соответствует каталогу')
        try: fcntl.flock(иной, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError: pass
        else: raise ValueError('Замок не принадлежит вызывающему')
        fcntl.flock(замок, fcntl.LOCK_EX | fcntl.LOCK_NB)
    finally: os.close(иной)


def _наблюдение_создать(каталог, имя, байты, *, чтение=False):
    номер = os.open(имя, os.O_RDWR | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=каталог)
    try:
        os.fchmod(номер, 0o600)
        смещение = 0
        while смещение < len(байты):
            число = os.write(номер, байты[смещение:смещение + 65536])
            if число <= 0: raise OSError('Запись входа наблюдения прервана')
            смещение += число
        os.fsync(номер); os.lseek(номер, 0, os.SEEK_SET)
        if чтение:
            читающий = os.open(имя, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=каталог)
            try:
                свой, другой = os.fstat(номер), _наблюдение_файл(читающий)
                if (свой.st_dev, свой.st_ino) != (другой.st_dev, другой.st_ino):
                    raise ValueError('Вход подменён до отправки')
            except BaseException: os.close(читающий); raise
            os.close(номер); номер = читающий
        return номер
    except BaseException: os.close(номер); raise


def _наблюдение_прочитать(номер, предел):
    до = _наблюдение_файл(номер)
    if до.st_size > предел: raise ValueError('Фактический файл превышает предел')
    результат = bytearray()
    while True:
        блок = os.pread(номер, min(65536, предел + 1 - len(результат)), len(результат))
        if not блок: break
        результат.extend(блок)
        if len(результат) > предел: raise ValueError('Файл вырос за предел')
    после = _наблюдение_файл(номер)
    if после.st_size != до.st_size or после.st_size != len(результат):
        raise ValueError('Файл изменился во время чтения')
    return bytes(результат)


def _наблюдение_квитанция(каталог, имя):
    номер = os.open(имя, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=каталог)
    try: байты = _наблюдение_прочитать(номер, 65536)
    finally: os.close(номер)
    def объект(пары):
        результат = {}
        for ключ, значение in пары:
            if ключ in результат: raise ValueError('Повтор поля квитанции')
            результат[ключ] = значение
        return результат
    return json.loads(байты, object_pairs_hook=объект)


def исполнить_под_наблюдением(*, наблюдатель, каталог, замок, аргументы, рабочий_каталог, среда, вход,
        родитель, проверка, исходник, тайм_аут_нс, предел_вывода, завершение_нс=2_000_000_000):
    if not all(hasattr(os, имя) for имя in ('waitid', 'WNOWAIT', 'WEXITED', 'WNOHANG')):
        raise ValueError('Нужен waitid/WNOWAIT; на macOS Python не ниже 3.13')
    if not os.path.isabs(sys.executable): raise ValueError('Неизвестен абсолютный интерпретатор родителя')
    _наблюдение_проверить_владение(каталог, замок)
    if not isinstance(наблюдатель, str) or not 1 <= len(наблюдатель.encode()) <= 256 * 1024:
        raise ValueError('Исходник наблюдателя должен помещаться в 256 KiB')
    if type(вход) is not bytes or len(вход) > 32 * 1024**2: raise ValueError('stdin превышает 32 MiB')
    for значение in (родитель, проверка):
        if not isinstance(значение, str) or str(uuid.UUID(значение)) != значение:
            raise ValueError('Нужен канонический UUID происхождения')
    if not isinstance(исходник, str) or len(исходник) != 64 or any(буква not in '0123456789abcdef' for буква in исходник):
        raise ValueError('Нужен точный SHA-256 происхождения')
    if (not isinstance(аргументы, list) or not 1 <= len(аргументы) <= 256
            or any(not isinstance(часть, str) or '\0' in часть for часть in аргументы)
            or not os.path.isabs(аргументы[0])):
        raise ValueError('Нужен точный argv с абсолютной программой')
    if (not isinstance(рабочий_каталог, str) or not os.path.isabs(рабочий_каталог)
            or Path(рабочий_каталог).resolve() != Path(рабочий_каталог)):
        raise ValueError('Нужен физический абсолютный cwd')
    if (not isinstance(среда, dict) or any(not isinstance(ключ, str) or not isinstance(значение, str)
            or not ключ or '=' in ключ or '\0' in ключ + значение for ключ, значение in среда.items())):
        raise ValueError('Нужна точная строковая среда')
    if (not _наблюдение_целое(тайм_аут_нс, 1, 86_400_000_000_000)
            or not _наблюдение_целое(предел_вывода, 1, 32 * 1024**2)
            or not _наблюдение_целое(завершение_нс, 1_000_000, 2_000_000_000)):
        raise ValueError('Неверный срок или предел наблюдения')
    идентификатор = str(uuid.uuid4())
    данные = dict(схема='fum.наблюдатель-команды.1', идентификатор=идентификатор, родитель=родитель,
        проверка=проверка, исходник=исходник, аргументы=аргументы, каталог=рабочий_каталог, среда=среда,
        срок_нс=time.monotonic_ns() + тайм_аут_нс, предел_вывода=предел_вывода, завершение_нс=завершение_нс)
    описание = _наблюдение_кодировать(данные)
    if len(описание) > 65536: raise ValueError('Конфигурация превышает 64 KiB')
    имена = {вид: 'команда-' + идентификатор + '-' + вид + ('.json' if вид == 'описание' else '.bin')
             for вид in ('описание', 'вход', 'вывод', 'ошибки')}
    свои = set(); жизнь = None; процесс = None
    def закрыть_жизнь():
        nonlocal жизнь
        if жизнь is not None:
            os.close(жизнь); свои.discard(жизнь); жизнь = None
    try:
        дескрипторы = {'каталог': каталог, 'замок': замок}
        for вид, байты in (('описание', описание), ('вход', вход), ('вывод', b''), ('ошибки', b'')):
            номер = _наблюдение_создать(каталог, имена[вид], байты, чтение=вид in ('описание', 'вход'))
            свои.add(номер); дескрипторы[вид] = номер
        чтение, жизнь = os.pipe(); свои.update((чтение, жизнь)); дескрипторы['жизнь'] = чтение
        команда = [sys.executable, '-I', '-S', '-B', '-c', наблюдатель,
            *[часть for имя, номер in дескрипторы.items() for часть in ('--' + имя, str(номер))]]
        манифест = dict(схема='fum.отправка-наблюдателя.1', идентификатор=идентификатор,
            аргументы=команда, дескрипторы=дескрипторы, файлы=имена, описание=описание.decode(),
            описание_sha256=hashlib.sha256(описание).hexdigest(), наблюдатель_sha256=hashlib.sha256(наблюдатель.encode()).hexdigest(),
            вход_sha256=hashlib.sha256(вход).hexdigest(), вход_байт=len(вход))
        байты = _наблюдение_кодировать(манифест)
        if len(байты) > 1024**2: raise ValueError('Манифест превышает 1 MiB')
        номер = _наблюдение_создать(каталог, 'отправка-наблюдателя-' + идентификатор + '.json', байты, чтение=True)
        свои.add(номер); os.fsync(каталог)
        процесс = subprocess.Popen(команда, pass_fds=tuple(дескрипторы.values()), close_fds=True,
            start_new_session=True, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        os.close(чтение); свои.discard(чтение)
        if процесс.wait() != 0: raise RuntimeError('Наблюдатель не подтвердил квитанцию')
        основа = {ключ: данные[ключ] for ключ in ('идентификатор', 'родитель', 'проверка', 'исходник')}
        основа['описание_sha256'] = манифест['описание_sha256']
        начало = _наблюдение_квитанция(каталог, 'наблюдатель-' + идентификатор + '-начало.json')
        if начало != {**основа, 'схема': 'fum.начало-наблюдателя.1'}: raise ValueError('Чужое начало наблюдения')
        итог = _наблюдение_квитанция(каталог, 'наблюдатель-' + идентификатор + '-конец.json')
        поля = set(основа) | {'схема', 'причина', 'исход', 'код_команды', 'длительность_нс',
            'вывод_байт', 'ошибки_байт', 'сигнал_TERM', 'сигнал_KILL', 'группа_исчезла'}
        причины = {'завершение', 'родитель_исчез', 'протокол_жизни', 'сигнал_наблюдателя', 'срок',
            'вывод', 'ошибка_наблюдателя', 'ошибка_вывода', 'канал_не_закрыт'}
        if (not isinstance(итог, dict) or set(итог) != поля or any(итог[ключ] != значение for ключ, значение in основа.items())
                or итог['схема'] != 'fum.квитанция-наблюдателя.1' or итог['причина'] not in причины
                or any(type(итог[ключ]) is not bool for ключ in ('сигнал_TERM', 'сигнал_KILL', 'группа_исчезла'))
                or итог['группа_исчезла'] is not True
                or any(not _наблюдение_целое(итог[ключ], 0, 2**63 - 1) for ключ in ('длительность_нс', 'вывод_байт', 'ошибки_байт'))
                or итог['код_команды'] is not None and not _наблюдение_целое(итог['код_команды'], -255, 255)):
            raise ValueError('Квитанция имеет чужое происхождение или неверные типы')
        переполнение = any(итог[вид + '_байт'] > предел_вывода for вид in ('вывод', 'ошибки'))
        if (итог['причина'] == 'завершение' and переполнение
                or итог['причина'] == 'вывод' and not переполнение):
            raise ValueError('Причина квитанции не соответствует пределу вывода')
        успех = итог['причина'] == 'завершение' and итог['код_команды'] == 0
        if итог['исход'] != ('успех' if успех else 'ошибка') or итог['причина'] == 'завершение' and итог['код_команды'] is None:
            raise ValueError('Квитанция противоречит исходу команды')
        выходы = {}
        for вид in ('вывод', 'ошибки'):
            выходы[вид] = _наблюдение_прочитать(дескрипторы[вид], предел_вывода)
            if len(выходы[вид]) != min(итог[вид + '_байт'], предел_вывода):
                raise ValueError('Размер выходного файла не совпадает с квитанцией')
        return dict(идентификатор=идентификатор, причина=итог['причина'], исход=итог['исход'],
                    код_команды=итог['код_команды'], квитанция=итог, **выходы)
    except BaseException:
        закрыть_жизнь()
        if процесс is not None:
            while True:
                try: процесс.wait(); break
                except (KeyboardInterrupt, InterruptedError): continue
        raise
    finally:
        закрыть_жизнь()
        for номер in свои: os.close(номер)

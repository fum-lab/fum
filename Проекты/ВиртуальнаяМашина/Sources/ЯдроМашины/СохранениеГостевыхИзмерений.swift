import Foundation

enum СохранениеГостевыхИзмерений {
    private struct Пакет: Encodable {
        let схема = "fum.измерения-гостя.1"
        let машина: String
        let план: String
        let проверка: String
        let исходник: String
        let файлы: [ФайлГостевогоИзмерения]
    }
    static func принять(_ пакет: Data, манифест: МанифестГотовностиГостя, хранилище: Хранилище) throws -> СводкаГостевыхИзмерений {
        try манифест.проверитьХранилище(хранилище)
        guard try хранилище.есть(манифест.имя),
              try хранилище.прочитать(манифест.имя) == кодировать(манифест) else {
            throw ОшибкаМашины("Импорт требует прежнего долговечно сохранённого точного запроса.")
        }
        let контекст = манифест.контекст
        let имя = "измерения-гостя-" + контекст.проверка + ".json"
        let прежнее = try хранилище.есть(имя) ? хранилище.прочитать(имя) : nil
        let сводка = try ИмпортГостевыхИзмерений.свести((прежнее.map { [$0] } ?? []) + [пакет], контекст: контекст)
        let итог = try кодировать(Пакет(машина: контекст.машина, план: контекст.план,
            проверка: контекст.проверка, исходник: контекст.исходник, файлы: сводка.файлы))
        guard итог.count <= 4 * 1024 * 1024 else {
            throw ОшибкаМашины("Закодированная история измерений превышает 4 MiB; прежняя история сохранена.")
        }
        if прежнее != итог { try хранилище.записать(имя, байты: итог) }
        return сводка
    }
}

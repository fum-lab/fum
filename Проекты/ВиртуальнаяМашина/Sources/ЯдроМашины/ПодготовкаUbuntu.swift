public func виртуальныйРазмерОбраза(_ данные: Data, предел: UInt64) throws -> UInt64 {
    struct Сведения: Decodable {
        var форматОбраза: String
        var размер: UInt64
        var основа: String?
        enum CodingKeys: String, CodingKey { case форматОбраза = "format", размер = "virtual-size", основа = "backing-filename" }
    }
    let сведения = try JSONDecoder().decode(Сведения.self, from: данные)
    guard сведения.форматОбраза == "qcow2", сведения.основа == nil, сведения.размер > 0, сведения.размер <= предел else {
        throw ОшибкаМашины("Образ имеет неподдержанные формат, размер или внешнюю основу.")
    }
    return сведения.размер
}

private struct СвидетельствоПодписи: Codable {
    var схема = "fum.подпись-образа.1"
    var план: String
    var образ: String
    var ключ: String
    var файлы: [String: String]
}

public final class ПодготовкаУбунту {
    public func подписьПодтверждена() throws -> Bool {
        guard try хранилище.есть("подпись-проверена.json"),
              let запись = try? JSONDecoder().decode(СвидетельствоПодписи.self, from: хранилище.прочитать("подпись-проверена.json")),
              запись.схема == "fum.подпись-образа.1", запись.план == план.отпечаток,
              запись.образ == план.хэшОбраза, запись.ключ == план.ключПодписи, запись.файлы.count == 3 else { return false }
        for (имя, хэш) in запись.файлы {
            guard try хранилище.есть(имя), try хэшФайла(имя) == хэш else { return false }
        }
        return true
    }
    public let хранилище: Хранилище
    public let метрики: МетрикиМашины
    public var план: ПланМашины { хранилище.паспорт.план }
    public init(_ хранилище: Хранилище) {
        self.хранилище = хранилище; метрики = МетрикиМашины(хранилище)
    }
    public func путь(_ имя: String) -> String { хранилище.путь + "/" + имя }
    public func этап(_ имя: String, проверить: () throws -> Bool, действие: () throws -> Void) throws {
        try метрики.измерить(имя) {
            try Конвейер.шаг(проверить: проверить) {
                try хранилище.записать("этап-" + имя + ".json", байты: кодировать(["состояние": "выполняется", "план": план.отпечаток]))
                try действие()
            }
            try хранилище.записать("этап-" + имя + ".json", байты: кодировать(["состояние": "завершена", "план": план.отпечаток]))
        }
    }
    public func зависимости() throws {
        try этап("зависимости", проверить: { Хост.инструмент("qemu-img") != nil && Хост.инструмент("gpg") != nil && Хост.инструмент("gpgv") != nil }) {
            let недостающие = [("qemu-img", "qemu"), ("gpgv", "gnupg")].filter { Хост.инструмент($0.0) == nil }.map { $0.1 }
            guard !недостающие.isEmpty else { throw ОшибкаМашины("Установка GnuPG неполна; проверьте пакет gnupg.") }
            // Только готовые bottles: сборка из исходников требует отдельного ресурсного окна.
            try метрики.команда("установка необходимых пакетов Homebrew", try Хост.обязательный("brew"),
                ["install", "--force-bottle"] + недостающие, предел: 1200,
                среда: ["HOMEBREW_NO_AUTO_UPDATE": "1", "HOMEBREW_NO_INSTALL_CLEANUP": "1",
                        "HOMEBREW_NO_INSTALLED_DEPENDENTS_CHECK": "1", "HOMEBREW_NO_ANALYTICS": "1"])
        }
    }
    public func хэшФайла(_ имя: String) throws -> String {
        let файл = try хранилище.открытьФайл(имя)
        let поток = FileHandle(fileDescriptor: файл, closeOnDealloc: true)
        var накопитель = SHA256()
        while let байты = try поток.read(upToCount: 1024 * 1024), !байты.isEmpty { накопитель.update(data: байты) }
        return накопитель.finalize().map { String(format: "%02x", $0) }.joined()
    }
    public func новыйФайл(_ префикс: String) throws -> String {
        let имя = префикс + "-" + UUID().uuidString.lowercased()
        try хранилище.записать(имя, байты: Data())
        return имя
    }
    public func установить(_ временный: String, как имя: String) throws {
        let файл = try хранилище.открытьФайл(временный)
        defer { close(файл) }
        guard fsync(файл) == 0,
              renameatx_np(хранилище.дескриптор, временный, хранилище.дескриптор, имя, UInt32(RENAME_EXCL)) == 0,
              fsync(хранилище.дескриптор) == 0 else { throw ОшибкаМашины("Не удалось установить новый артефакт без замены существующего: \(имя).") }
    }
    private func скачать(_ адрес: String, в имя: String, продолжить: Bool = false, максимум: UInt64 = 4 * 1024 * 1024) throws {
        var аргументы = ["-q", "--fail", "--location", "--proto", "=https", "--proto-redir", "=https",
                         "--connect-timeout", "20", "--max-time", "900", "--retry", "2", "--retry-delay", "1",
                         "--max-filesize", String(максимум), "--output", путь(имя)]
        if продолжить { аргументы += ["--continue-at", "-"] }
        аргументы.append(адрес)
        try метрики.команда("получение официального источника", "/usr/bin/curl", аргументы, предел: 950)
    }
    private func проверитьПодпись() throws {
        let основа = URL(string: план.образ)!.deletingLastPathComponent().absoluteString
        let таблица = try новыйФайл("SHA256SUMS"), подпись = try новыйФайл("SHA256SUMS-gpg"), ключ = try новыйФайл("ключ-Ubuntu")
        try скачать(основа + "/SHA256SUMS", в: таблица)
        try скачать(основа + "/SHA256SUMS.gpg", в: подпись)
        try скачать("https://keyserver.ubuntu.com/pks/lookup?op=get&search=0x" + план.ключПодписи, в: ключ)
        let имяКаталога = "gpg-" + UUID().uuidString.lowercased()
        guard mkdirat(хранилище.дескриптор, имяКаталога, 0o700) == 0 else { throw ОшибкаМашины("Не удалось создать личный каталог GPG.") }
        let аргументы = ["--no-options", "--batch", "--no-autostart", "--homedir", путь(имяКаталога)]
        let сведения = try метрики.команда("проверка первичного отпечатка Ubuntu", try Хост.обязательный("gpg"),
            аргументы + ["--with-colons", "--show-keys", путь(ключ)])
        try ПроверкаОбраза.ключ(сведения.вывод, ожидаемый: план.ключПодписи)
        let кольцо = путь(имяКаталога) + "/ubuntu.gpg"
        try метрики.команда("подготовка отдельного keyring", try Хост.обязательный("gpg"),
            аргументы + ["--output", кольцо, "--dearmor", путь(ключ)])
        let результат = try метрики.команда("криптографическая проверка подписи", try Хост.обязательный("gpgv"),
            ["--homedir", путь(имяКаталога), "--keyring", кольцо, "--status-fd", "1", путь(подпись), путь(таблица)])
        try ПроверкаОбраза.подпись(результат.вывод, код: результат.код, ключ: план.ключПодписи)
        try ПроверкаОбраза.таблица(String(decoding: хранилище.прочитать(таблица), as: UTF8.self), план: план)
        try хранилище.записать("подпись-проверена.json", байты: кодировать(СвидетельствоПодписи(
            план: план.отпечаток, образ: план.хэшОбраза, ключ: план.ключПодписи,
            файлы: [таблица: try хэшФайла(таблица), подпись: try хэшФайла(подпись), ключ: try хэшФайла(ключ)])))
    }
    public func образ() throws {
        try этап("образ", проверить: {
            guard try хранилище.есть("образ.qcow2") else { return false }
            guard try хэшФайла("образ.qcow2") == план.хэшОбраза else { throw ОшибкаМашины("Сохранённый образ повреждён; диск не изменён.") }
            return try подписьПодтверждена()
        }) {
            try проверитьПодпись()
            // Восстановленное свидетельство не требует повторно получать уже проверенные байты.
            if try хранилище.есть("образ.qcow2"), try хэшФайла("образ.qcow2") == план.хэшОбраза { return }
            let имя = try новыйФайл("загрузка")
            if try хранилище.есть("незавершённая-загрузка.json") {
                let прежнее = try JSONDecoder().decode([String: String].self, from: хранилище.прочитать("незавершённая-загрузка.json"))
                if прежнее["план"] == план.отпечаток, let источник = прежнее["файл"], try хранилище.есть(источник) {
                    // Новая попытка не делит выходной файл с возможным живым потомком прерванной команды.
                    let вход = try хранилище.открытьФайл(источник), выход = try хранилище.открытьФайл(имя, запись: true)
                    defer { close(вход); close(выход) }
                    var сведения = stat()
                    guard fstat(вход, &сведения) == 0, сведения.st_size <= 2 << 30 else { throw ОшибкаМашины("Неверный размер частичной загрузки.") }
                    var осталось = сведения.st_size
                    var буфер = [UInt8](repeating: 0, count: 1024 * 1024)
                    while осталось > 0 {
                        let прочитано = Darwin.read(вход, &буфер, min(буфер.count, Int(осталось)))
                        guard прочитано > 0 else { throw ОшибкаМашины("Не удалось прочитать собственный префикс загрузки.") }
                        let записано = буфер.withUnsafeBytes { Darwin.write(выход, $0.baseAddress, прочитано) }
                        guard записано == прочитано else { throw ОшибкаМашины("Не удалось сохранить префикс загрузки.") }
                        осталось -= Int64(прочитано)
                    }
                }
            }
            try хранилище.записать("незавершённая-загрузка.json", байты: кодировать(["план": план.отпечаток, "файл": имя]))
            try скачать(план.образ, в: имя, продолжить: true, максимум: 2 << 30)
            try метрики.измерить("SHA-256 скачанного образа") {
                guard try хэшФайла(имя) == план.хэшОбраза else { throw ОшибкаМашины("SHA-256 скачанного образа не совпал. Образ не используется.") }
            }
            try установить(имя, как: "образ.qcow2")
        }
    }
    public func диск() throws {
        try этап("диск", проверить: {
            guard try хранилище.есть("диск.raw") else { return false }
            let ожидаемое = ["схема": "fum.конвертация-диска.1", "план": план.отпечаток, "образ": план.хэшОбраза,
                              "сравнение": "qemu-img compare: 0", "размер": String(UInt64(план.профиль.дискГиБ) << 30)]
            guard try хранилище.есть("диск-проверен.json"),
                  let запись = try? JSONDecoder().decode([String: String].self, from: хранилище.прочитать("диск-проверен.json")),
                  запись == ожидаемое else { throw ОшибкаМашины("Диск без действительного свидетельства конвертации сохранён для диагностики.") }
            let файл = try хранилище.открытьФайл("диск.raw"); defer { close(файл) }
            var сведения = stat()
            guard fstat(файл, &сведения) == 0, сведения.st_size == Int64(план.профиль.дискГиБ) << 30 else {
                throw ОшибкаМашины("Размер рабочего диска отличается от плана; диск сохранён.")
            }
            return true
        }) {
            try Хост.ресурсы(хранилище.путь).проверить(план.профиль)
            guard try хэшФайла("образ.qcow2") == план.хэшОбраза else { throw ОшибкаМашины("Исходный образ не прошёл SHA-256.") }
            let конвертер = try Хост.обязательный("qemu-img")
            let сведения = try метрики.команда("параметры QCOW2", конвертер, ["info", "--output=json", "-f", "qcow2", путь("образ.qcow2")])
            _ = try виртуальныйРазмерОбраза(Data(сведения.вывод.utf8), предел: UInt64(план.профиль.дискГиБ) << 30)
            let имя = try новыйФайл("конвертация")
            try метрики.команда("конвертация QCOW2 в RAW", конвертер, ["convert", "-f", "qcow2", "-O", "raw", путь("образ.qcow2"), путь(имя)], предел: 600)
            try метрики.команда("сравнение RAW с проверенным QCOW2", конвертер, ["compare", "-f", "qcow2", "-F", "raw", путь("образ.qcow2"), путь(имя)], предел: 300)
            let файл = try хранилище.открытьФайл(имя, запись: true); defer { close(файл) }
            guard ftruncate(файл, Int64(план.профиль.дискГиБ) << 30) == 0, fsync(файл) == 0 else { throw ОшибкаМашины("Не удалось увеличить рабочий диск.") }
            try хранилище.записать("диск-проверен.json", байты: кодировать([
                "схема": "fum.конвертация-диска.1", "план": план.отпечаток, "образ": план.хэшОбраза,
                "сравнение": "qemu-img compare: 0", "размер": String(UInt64(план.профиль.дискГиБ) << 30)]))
            try установить(имя, как: "диск.raw")
        }
    }
}

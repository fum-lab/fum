import Foundation

struct МанифестГотовностиГостя: Codable {
    let схема: String
    let контекст: КонтекстГостевыхИзмерений
    let исходник: Data
    let счётчик: Data
    let данные: Data
    let вход: Data

    static func создать(запуск: ЗапускМашины, родитель: String, проверка: String, коммит: String,
                        ожидаемыеДанные: String, исходник: String, счётчик: String) throws -> Self {
        let контекст = КонтекстГостевыхИзмерений(машина: запуск.машина, план: запуск.план, проверка: проверка,
            исходник: try исходныйОтпечаток(исходник: Data(исходник.utf8), счётчик: Data(счётчик.utf8)), родитель: родитель)
        let данные = try кодировать(["машина": запуск.машина, "план": запуск.план, "запуск": запуск.запуск,
            "проверка": проверка, "родитель": родитель, "счётчик": счётчик, "ожидаемые_данные": ожидаемыеДанные,
            "коммит": коммит, "исходник": контекст.исходник])
        let манифест = Self(схема: "fum.манифест-готовности.1", контекст: контекст,
            исходник: Data(исходник.utf8), счётчик: Data(счётчик.utf8), данные: данные,
            вход: ДоступКГостю.сценарий(исходник: исходник, вызов: "подтвердить_готовность", данные: данные))
        try манифест.проверить()
        return манифест
    }
    // Контракт v2: реализация появится после первого RED адресных сценариев.
    static func создать(запуск: ЗапускМашины, родитель: String, проверка: String, коммит: String,
                        ожидаемыеДанные: String, исходник: String, счётчик: String,
                        наблюдатель: String, родительНаблюдателя: String) throws -> Self {
        throw ОшибкаМашины("Манифест с наблюдателем ещё не реализован.")
    }
    private static func отпечаток(_ значение: String, длина: Int = 64) -> Bool {
        значение.utf8.count == длина && значение.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
    static func исходныйОтпечаток(исходник: Data, счётчик: Data) throws -> String {
        // Имена и отдельные байтовые значения сохраняют границы ресурсов.
        хэш(try кодировать(["готовность.py": исходник, "проверить-набор.py": счётчик]))
    }
    func проверить() throws {
        guard схема == "fum.манифест-готовности.1",
              [контекст.машина, контекст.проверка, контекст.родитель].allSatisfy({ UUID(uuidString: $0)?.uuidString.lowercased() == $0 }),
              Self.отпечаток(контекст.план), Self.отпечаток(контекст.исходник),
              исходник.count <= 512 * 1024, счётчик.count <= 512 * 1024, данные.count <= 1024 * 1024,
              вход.count <= 3 * 1024 * 1024,
              let программа = String(data: исходник, encoding: .utf8), !программа.isEmpty,
              let счётчикТекст = String(data: счётчик, encoding: .utf8), !счётчикТекст.isEmpty,
              try Self.исходныйОтпечаток(исходник: исходник, счётчик: счётчик) == контекст.исходник,
              let тело = try JSONSerialization.jsonObject(with: данные) as? [String: String],
              Set(тело.keys) == ["машина", "план", "запуск", "проверка", "родитель", "счётчик", "ожидаемые_данные", "коммит", "исходник"],
              тело["машина"] == контекст.машина, тело["план"] == контекст.план,
              тело["проверка"] == контекст.проверка, тело["родитель"] == контекст.родитель,
              тело["исходник"] == контекст.исходник, Data(тело["счётчик"]!.utf8) == счётчик,
              UUID(uuidString: тело["запуск"]!)?.uuidString.lowercased() == тело["запуск"],
              Self.отпечаток(тело["коммит"]!, длина: 40),
              тело["ожидаемые_данные"]!.isEmpty || Self.отпечаток(тело["ожидаемые_данные"]!),
              try кодировать(тело) == данные,
              ДоступКГостю.сценарий(исходник: программа, вызов: "подтвердить_готовность", данные: данные) == вход,
              try кодировать(self).count <= 4 * 1024 * 1024 else {
            throw ОшибкаМашины("Манифест не связывает точные байты исходников, запроса и отправки.")
        }
    }
    func входЭкспорта() throws -> Data {
        try проверить()
        let запрос = try кодировать(["машина": контекст.машина, "план": контекст.план,
            "проверка": контекст.проверка, "исходник": контекст.исходник])
        return ДоступКГостю.сценарий(исходник: String(data: исходник, encoding: .utf8)!,
            вызов: "экспортировать_измерения", данные: запрос)
    }
    var имя: String { "запрос-готовности-" + контекст.проверка + ".json" }
    func проверитьХранилище(_ хранилище: Хранилище) throws {
        try проверить()
        let тело = try JSONDecoder().decode([String: String].self, from: данные)
        guard контекст.машина == хранилище.паспорт.идентификатор,
              контекст.план == хранилище.паспорт.план.отпечаток,
              тело["коммит"] == хранилище.паспорт.план.профиль.коммит else {
            throw ОшибкаМашины("Манифест принадлежит другой VM или другому плану.")
        }
    }
    func сохранить(_ хранилище: Хранилище) throws {
        try проверитьХранилище(хранилище)
        let байты = try кодировать(self)
        if try хранилище.есть(имя) {
            guard try хранилище.прочитать(имя) == байты else {
                throw ОшибкаМашины("UUID проверки уже принадлежит другому сохранённому запросу.")
            }
            return
        }
        try хранилище.записать(имя, байты: байты)
    }
}

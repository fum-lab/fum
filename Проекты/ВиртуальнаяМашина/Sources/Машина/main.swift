import Foundation
import Darwin
import ЯдроМашины

umask(0o077)

func вывести<T: Encodable>(_ значение: T) throws { FileHandle.standardOutput.write(try кодировать(значение)) }
func прочитать<T: Decodable>(_ тип: T.Type, _ путь: String) throws -> T {
    let адрес = URL(fileURLWithPath: NSString(string: путь).expandingTildeInPath)
    let свойства = try FileManager.default.attributesOfItem(atPath: адрес.path)
    guard (свойства[.size] as? NSNumber)?.intValue ?? Int.max <= 4 * 1024 * 1024 else { throw ОшибкаМашины("Входной JSON превышает 4 MiB.") }
    return try JSONDecoder().decode(тип, from: Data(contentsOf: адрес))
}

do {
    let аргументы = Array(CommandLine.arguments.dropFirst())
    let команда = аргументы.first ?? "помощь"
    var параметры: [String: String] = [:]
    var индекс = 1
    while индекс < аргументы.count {
        guard аргументы[индекс].hasPrefix("--"), индекс + 1 < аргументы.count,
              параметры[аргументы[индекс]] == nil else { throw ОшибкаМашины("Параметры задаются один раз парами --имя значение.") }
        параметры[аргументы[индекс]] = аргументы[индекс + 1]; индекс += 2
    }
    let разрешённые = Set(["--каталог", "--профиль", "--план", "--до", "--команда"])
    guard Set(параметры.keys).isSubset(of: разрешённые) else { throw ОшибкаМашины("Неизвестный параметр команды.") }
    let каталог = NSString(string: параметры["--каталог"] ?? "/Users/Shared/FUM-VM-\(getuid())/ubuntu-noble-arm64").expandingTildeInPath
    switch команда {
    case "помощь":
        print("""
        Настройка виртуальной машины
          профиль                             JSON первого профиля
          проверить [--каталог ПУТЬ]           сведения о Mac, ресурсах и зависимостях
          план [--каталог ПУТЬ] [--профиль JSON]  план без записи; сохраните stdout вне Git
          подготовить --план JSON --до зависимости|образ|диск|всё
          запустить [--каталог ПУТЬ]           отдельный процесс VZ с постоянным диском
          состояние [--каталог ПУТЬ]           ответ именно текущего процесса
          готовность [--каталог ПУТЬ]          проверка Linux и переносимого профиля
          ssh [--каталог ПУТЬ] [--команда ТЕКСТ]
          остановить [--каталог ПУТЬ]          запрос гостю и подтверждение остановки
        Образ и состояние создаются вне Git. По умолчанию устанавливаются только отсутствующие
        qemu/gnupg в виде Homebrew bottles; прежние VM и пользовательские настройки сохраняются.
        Совместимость VZ и готовность ещё проходят реальные испытания.
        """)
    case "профиль": try вывести(Профиль())
    case "проверить": try вывести(Хост.снимок(каталог))
    case "план":
        let профиль = try параметры["--профиль"].map { try прочитать(Профиль.self, $0) } ?? Профиль()
        try вывести(ПланМашины.создать(профиль: профиль, каталог: каталог, ресурсы: Хост.ресурсы(каталог)))
    case "подготовить":
        guard let вход = параметры["--план"], let граница = параметры["--до"], ["зависимости", "образ", "диск", "всё"].contains(граница) else {
            throw ОшибкаМашины("Нужны --план JSON и --до зависимости|образ|диск|всё.")
        }
        let план = try прочитать(ПланМашины.self, вход)
        try план.проверить()
        try Хост.ресурсы(план.каталог).проверить(план.профиль)
        let хранилище = try Хранилище(план: план, создать: true)
        let подготовка = ПодготовкаUbuntu(хранилище)
        try подготовка.метрики.измерить("подготовка до этапа «\(граница)»") {
            try хранилище.записать("снимок-хоста.json", байты: кодировать(Хост.снимок(план.каталог)))
            try подготовка.зависимости()
            if граница != "зависимости" { try подготовка.образ() }
            if ["диск", "всё"].contains(граница) { try подготовка.диск() }
            if граница == "всё" { try подготовка.идентичность() }
        }
        try вывести(["результат": "этап подготовки проверен", "этап": граница, "VM": хранилище.паспорт.идентификатор])
    case "служить":
        if getpgrp() != getpid() { guard setsid() >= 0 else { throw ОшибкаМашины("Не удалось изолировать службу VM.") } }
        let читатель = try ЧтениеХранилища(каталог)
        let служба = try СлужбаVZ(читатель.паспорт.план)
        try служба.запустить()
        withExtendedLifetime(служба) { dispatchMain() }
    case "запустить", "состояние", "готовность", "остановить", "ssh":
        let клиент = try КлиентМашины(каталог)
        if команда == "ssh" { try клиент.ssh(параметры["--команда"]) }
        var результат: ЗапускМашины
        switch команда {
        case "запустить":
            guard let физический = realpath(CommandLine.arguments[0], nil) else { throw ОшибкаМашины("Не удалось определить собственный исполняемый файл.") }
            defer { free(физический) }
            результат = try клиент.начать(String(cString: физический))
        case "готовность": результат = try клиент.готовность()
        case "остановить": результат = try клиент.остановить()
        default: результат = try клиент.состояние()
        }
        результат.токен = ""
        try вывести(результат)
    default: throw ОшибкаМашины("Неизвестная команда; выполните «помощь».")
    }
} catch {
    FileHandle.standardError.write(Data("Ошибка: \(error)\n".utf8))
    exit(1)
}

"""Открытые фикстуры родителя; все payload и квитанции остаются во временном каталоге."""
import fcntl
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import unittest
from unittest import mock


ресурсы = Path(__file__).resolve().parents[2] / 'Sources/ЯдроМашины/Ресурсы'
путь_адаптера = ресурсы / 'родитель_наблюдателя.py'
путь_наблюдателя = ресурсы / 'наблюдатель.py'
фикстура = Path(__file__).with_name('test_наблюдатель.py')


def загрузить():
    область = {'__name__': 'открытая_фикстура_адаптера'}
    exec(compile(путь_адаптера.read_text(), '<родитель_наблюдателя>', 'exec'), область)
    assert '__file__' not in область
    return область


def параметры(корень, каталог, замок, режим='успех'):
    return dict(наблюдатель=путь_наблюдателя.read_text(), каталог=каталог, замок=замок,
        аргументы=[sys.executable, '-B', str(фикстура), '--команда', str(корень), режим],
        рабочий_каталог=str(корень), среда={'PATH': '/usr/bin:/bin'}, вход='точные байты\n'.encode(),
        родитель='12345678-1234-4234-8234-123456789abc', проверка='22345678-1234-4234-8234-123456789abc',
        исходник='a' * 64, тайм_аут_нс=4_000_000_000, предел_вывода=65536, завершение_нс=250_000_000)


def открыть(корень):
    каталог = os.open(корень, os.O_RDONLY | os.O_DIRECTORY)
    замок = os.open(корень / 'замок', os.O_CREAT | os.O_RDWR, 0o600)
    fcntl.flock(замок, fcntl.LOCK_EX | fcntl.LOCK_NB)
    return каталог, замок


def исказить_квитанцию(исходник, правка):
    вставка = "def кодировать(значение):\n    if isinstance(значение, dict) and значение.get('схема') == 'fum.квитанция-наблюдателя.1':\n        значение = dict(значение)\n        " + правка + "\n"
    assert исходник.count('def кодировать(значение):\n') == 1
    return исходник.replace('def кодировать(значение):\n', вставка)


class ПроверкиРодителяНаблюдателя(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name).resolve()

    def свои_дескрипторы(сам):
        каталог, замок = открыть(сам.корень)
        сам.addCleanup(os.close, каталог); сам.addCleanup(os.close, замок)
        return каталог, замок

    def свободен(сам):
        номер = os.open(сам.корень / 'замок', os.O_RDWR)
        try:
            try: fcntl.flock(номер, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError: return False
            return True
        finally: os.close(номер)

    def дождаться(сам, условие, предел=5):
        срок = time.monotonic() + предел
        while time.monotonic() < срок:
            if условие(): return
            time.sleep(0.01)
        сам.fail('Не получено свидетельство настоящего процесса')

    def test_точные_байты_манифест_повтор_и_владение_дескрипторами(сам):
        выполнить = загрузить()['исполнить_под_наблюдением']
        каталог, замок = сам.свои_дескрипторы()
        вход = параметры(сам.корень, каталог, замок)
        вход['аргументы'] = [sys.executable, '-c', 'import os,sys; os.write(1,sys.argv[1].encode()+b"\\0"+os.environ["OPEN_VALUE"].encode()+b"\\0"+sys.stdin.buffer.read())', 'байты с пробелом']
        вход['среда'] = {'OPEN_VALUE': 'значение ё'}
        первый = выполнить(**вход)
        сам.assertEqual(первый['вывод'], 'байты с пробелом\0значение ё\0точные байты\n'.encode())
        сам.assertEqual((первый['исход'], первый['код_команды'], первый['ошибки']), ('успех', 0, b''))
        сам.assertFalse(сам.свободен()); os.fstat(каталог); os.fstat(замок)
        сохранённые = {путь.name: путь.read_bytes() for путь in сам.корень.iterdir() if путь.name != 'замок'}
        манифест = json.loads(next(сам.корень.glob('отправка-наблюдателя-*.json')).read_bytes())
        сам.assertEqual(манифест['схема'], 'fum.отправка-наблюдателя.1')
        конфигурация = (сам.корень / манифест['файлы']['описание']).read_bytes()
        сам.assertEqual(манифест['описание'].encode(), конфигурация)
        сам.assertEqual(манифест['описание_sha256'], hashlib.sha256(конфигурация).hexdigest())
        сам.assertEqual(манифест['наблюдатель_sha256'], hashlib.sha256(вход['наблюдатель'].encode()).hexdigest())
        сам.assertEqual(манифест['аргументы'][5], вход['наблюдатель'])
        сам.assertEqual((сам.корень / манифест['файлы']['вход']).read_bytes(), вход['вход'])
        сам.assertEqual(манифест['вход_sha256'], hashlib.sha256(вход['вход']).hexdigest())
        сам.assertEqual(манифест['вход_байт'], len(вход['вход']))
        второй = выполнить(**вход)
        сам.assertNotEqual(первый['идентификатор'], второй['идентификатор'])
        for имя, байты in сохранённые.items(): сам.assertEqual((сам.корень / имя).read_bytes(), байты)

    def test_код_наблюдателя_ноль_не_делает_команду_успешной(сам):
        выполнить = загрузить()['исполнить_под_наблюдением']
        каталог, замок = сам.свои_дескрипторы()
        итог = выполнить(**параметры(сам.корень, каталог, замок, 'отказ'))
        сам.assertEqual((итог['исход'], итог['код_команды'], итог['причина']), ('ошибка', 17, 'завершение'))
        сам.assertEqual(итог['ошибки'], 'ошибка'.encode())
        сам.assertFalse(сам.свободен())

    def test_срок_и_вывод_ограничены_с_проверенной_квитанцией(сам):
        выполнить = загрузить()['исполнить_под_наблюдением']
        каталог, замок = сам.свои_дескрипторы()
        for режим, причина in [('семейство', 'срок'), ('поток', 'вывод')]:
            with сам.subTest(режим=режим):
                вход = параметры(сам.корень, каталог, замок, режим)
                вход['тайм_аут_нс'] = 600_000_000; вход['предел_вывода'] = 512
                итог = выполнить(**вход)
                сам.assertEqual((итог['исход'], итог['причина']), ('ошибка', причина))
                сам.assertLessEqual(len(итог['вывод']), 512)
                сам.assertTrue(итог['квитанция']['группа_исчезла'])
                сам.assertFalse(сам.свободен())

    def test_убийство_только_родителя_сохраняет_результат_и_замок_до_очистки(сам):
        процесс = subprocess.Popen([sys.executable, '-B', __file__, '--родитель', str(сам.корень)],
            stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        try:
            сам.дождаться(lambda: (сам.корень / 'пульс').exists())
            сам.assertFalse(сам.свободен())
            процесс.kill(); процесс.wait(timeout=3)
            сам.assertFalse(сам.свободен())
            сам.дождаться(lambda: len(list(сам.корень.glob('наблюдатель-*-конец.json'))) == 1)
            сам.дождаться(сам.свободен)
            квитанция = json.loads(next(сам.корень.glob('наблюдатель-*-конец.json')).read_bytes())
            сам.assertEqual(квитанция['причина'], 'родитель_исчез')
            сам.assertTrue(квитанция['группа_исчезла'])
            манифест = json.loads(next(сам.корень.glob('отправка-наблюдателя-*.json')).read_bytes())
            for имя in манифест['файлы'].values(): сам.assertTrue((сам.корень / имя).is_file())
            размер = (сам.корень / 'пульс').stat().st_size
            time.sleep(0.1); сам.assertEqual((сам.корень / 'пульс').stat().st_size, размер)
        finally:
            if процесс.poll() is None: процесс.kill(); процесс.wait(timeout=3)
            процесс.stderr.close()

    def test_пределы_до_запуска_не_оставляют_команду(сам):
        выполнить = загрузить()['исполнить_под_наблюдением']
        каталог, замок = сам.свои_дескрипторы()
        for поле, значение in [('наблюдатель', '#' * (256 * 1024 + 1)), ('среда', {'OPEN': 'x' * 65536}), ('тайм_аут_нс', True)]:
            with сам.subTest(поле=поле):
                вход = параметры(сам.корень, каталог, замок); вход[поле] = значение
                with сам.assertRaises((ValueError, RuntimeError)): выполнить(**вход)
                сам.assertFalse((сам.корень / 'число-команд').exists())
                сам.assertFalse(сам.свободен()); os.fstat(каталог); os.fstat(замок)

    def test_переполнение_не_может_быть_успехом_при_обрезанном_файле(сам):
        выполнить = загрузить()['исполнить_под_наблюдением']
        каталог, замок = сам.свои_дескрипторы()
        for правка in ["значение['вывод_байт'] += 1", "значение['причина'] = 'вывод'; значение['исход'] = 'ошибка'"]:
            with сам.subTest(правка=правка):
                вход = параметры(сам.корень, каталог, замок)
                вход['предел_вывода'] = len(вход['вход'])
                вход['наблюдатель'] = исказить_квитанцию(вход['наблюдатель'], правка)
                with сам.assertRaises((ValueError, RuntimeError)): выполнить(**вход)
                сам.assertFalse(сам.свободен())

    def test_подмена_происхождения_типов_дублей_и_размера_отвергается(сам):
        выполнить = загрузить()['исполнить_под_наблюдением']
        каталог, замок = сам.свои_дескрипторы()
        правки = ["значение['описание_sha256'] = 'b' * 64", "значение['исходник'] = 'b' * 64",
            "значение['проверка'] = '32345678-1234-4234-8234-123456789abc'",
            "значение['родитель'] = '32345678-1234-4234-8234-123456789abc'",
            "значение['идентификатор'] = '32345678-1234-4234-8234-123456789abc'",
            "значение['длительность_нс'] = True", "значение['код_команды'] = True",
            "значение['вывод_байт'] = True", "значение['группа_исчезла'] = 1",
            "значение['вывод_байт'] += 1", "значение['исход'] = 'ошибка'",
            "return ('{\\\"исход\\\":\\\"ошибка\\\",' + json.dumps(значение, ensure_ascii=False)[1:]).encode()"]
        for правка in правки:
            with сам.subTest(правка=правка):
                вход = параметры(сам.корень, каталог, замок)
                вход['наблюдатель'] = исказить_квитанцию(вход['наблюдатель'], правка)
                до = set(сам.корень.glob('отправка-наблюдателя-*.json'))
                with сам.assertRaises((ValueError, RuntimeError)): выполнить(**вход)
                новые = set(сам.корень.glob('отправка-наблюдателя-*.json')) - до
                сам.assertEqual(len(новые), 1)
                номер = json.loads(новые.pop().read_bytes())['идентификатор']
                сам.assertTrue((сам.корень / ('наблюдатель-' + номер + '-конец.json')).exists())
                сам.assertFalse(сам.свободен())

    def test_исключение_закрывает_жизнь_и_ждёт_потомков_до_возврата(сам):
        область = загрузить()
        каталог, замок = сам.свои_дескрипторы()
        исходный = subprocess.Popen
        def создать(*аргументы, **ключи):
            процесс = исходный(*аргументы, **ключи)
            ожидать = процесс.wait; первое = True
            def прервать(*части, **настройки):
                nonlocal первое
                if первое:
                    первое = False
                    сам.дождаться(lambda: (сам.корень / 'пульс').exists())
                    raise RuntimeError('Открытая ошибка ожидания')
                return ожидать(*части, **настройки)
            процесс.wait = прервать
            return процесс
        with mock.patch.object(область['subprocess'], 'Popen', создать):
            with сам.assertRaisesRegex(RuntimeError, 'Открытая ошибка ожидания'):
                область['исполнить_под_наблюдением'](**параметры(сам.корень, каталог, замок, 'семейство'))
        квитанция = json.loads(next(сам.корень.glob('наблюдатель-*-конец.json')).read_bytes())
        сам.assertEqual(квитанция['причина'], 'родитель_исчез')
        сам.assertTrue(квитанция['группа_исчезла'])
        размер = (сам.корень / 'пульс').stat().st_size
        time.sleep(0.1); сам.assertEqual((сам.корень / 'пульс').stat().st_size, размер)
        сам.assertFalse(сам.свободен()); os.fstat(каталог); os.fstat(замок)

    def test_подмена_входа_FIFO_не_блокирует_родителя_до_наблюдения(сам):
        процесс = subprocess.Popen([sys.executable, '-B', __file__, '--подмена-fifo', str(сам.корень)],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        try:
            try: вывод, ошибки = процесс.communicate(timeout=2)
            except subprocess.TimeoutExpired: сам.fail('FIFO заблокировал родителя до запуска наблюдателя')
            сам.assertEqual(процесс.returncode, 0, ошибки.decode())
            сам.assertEqual(вывод, 'отклонено\n'.encode())
            сам.assertFalse(list(сам.корень.glob('наблюдатель-*.json')))
            сам.assertTrue(сам.свободен())
        finally:
            if процесс.poll() is None: процесс.kill(); процесс.wait(timeout=3)
            процесс.stdout.close(); процесс.stderr.close()


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == '--подмена-fifo':
        корень = Path(sys.argv[2]); каталог, замок = открыть(корень)
        область = загрузить(); исходный = os.open
        def подменить(имя, флаги, *части, **ключи):
            if str(имя).endswith('-описание.json') and not флаги & os.O_CREAT:
                os.unlink(имя, dir_fd=каталог); os.mkfifo(имя, 0o600, dir_fd=каталог)
            return исходный(имя, флаги, *части, **ключи)
        try:
            with mock.patch.object(область['os'], 'open', подменить):
                try: область['исполнить_под_наблюдением'](**параметры(корень, каталог, замок))
                except ValueError: print('отклонено')
                else: raise AssertionError('FIFO принят')
        finally: os.close(каталог); os.close(замок)
    elif len(sys.argv) > 1 and sys.argv[1] == '--родитель':
        корень = Path(sys.argv[2]); каталог, замок = открыть(корень)

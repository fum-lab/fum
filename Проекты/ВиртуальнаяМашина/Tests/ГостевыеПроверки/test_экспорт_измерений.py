"""Экспорт хранит реальные фазы, исходные байты и точную проверку без записи."""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest import mock

ресурс = Path(__file__).resolve().parents[2] / 'Sources/ЯдроМашины/Ресурсы/готовность.py'
спецификация = importlib.util.spec_from_file_location('экспорт_измерений_гостя', ресурс)
модуль = importlib.util.module_from_spec(спецификация); спецификация.loader.exec_module(модуль)


class ПроверкиЭкспортаИзмерений(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory()
        сам.addCleanup(сам.временный.cleanup)
        сам.корень = Path(сам.временный.name).resolve() / 'гость'
        сам.проверка = '12345678-1234-4234-8234-123456789abc'
        сам.событие = {'идентификатор': '22345678-1234-4234-8234-123456789abc',
            'родитель': '32345678-1234-4234-8234-123456789abc', 'операция': 'Открытая команда',
            'исход': 'выполняется', 'длительностьНс': None, 'происхождение': 'a' * 64, 'запуск': сам.проверка}
        сам.владелец = {'схема': 'открытая-фикстура.1'}

    def создать(сам, каталог, фаза, **изменения):
        событие = dict(сам.событие, **изменения)
        имя = фаза + '-' + событие['идентификатор'] + '.json'
        модуль.установить_свидетельство(каталог, имя, событие)
        return сам.корень / имя

    def собрать(сам, каталог):
        return модуль.собрать_измерения(каталог, сам.проверка, 'a' * 64)

    def test_исходные_байты_и_фазы_сохраняются_повтор_одинаков(сам):
        with модуль.область_гостя(сам.корень, сам.владелец) as каталог:
            сам.создать(каталог, 'начало')
            сам.создать(каталог, 'конец', исход='успех', длительностьНс=100)
            сам.создать(каталог, 'начало', идентификатор='42345678-1234-4234-8234-123456789abc', запуск='52345678-1234-4234-8234-123456789abc')
            снимок = {путь.name: путь.read_bytes() for путь in сам.корень.iterdir()}
            результат = сам.собрать(каталог)
            сам.assertEqual(результат, сам.собрать(каталог))
            сам.assertEqual(len(результат), 2)
            for запись in результат:
                байты = снимок[запись['имя']]
                сам.assertEqual(запись['данные'].encode(), байты)
                сам.assertEqual(запись['sha256'], hashlib.sha256(байты).hexdigest())
            сам.assertEqual(снимок, {путь.name: путь.read_bytes() for путь in сам.корень.iterdir()})

    def test_одиночная_фаза_остаётся_неполной(сам):
        with модуль.область_гостя(сам.корень, сам.владелец) as каталог:
            сам.создать(каталог, 'начало')
            результат = сам.собрать(каталог)
            сам.assertEqual(len(результат), 1)
            сам.assertEqual(json.loads(результат[0]['данные'])['исход'], 'выполняется')

    def test_чужой_исходник_и_неверная_фаза_отклоняются(сам):
        for изменения in ({'происхождение': 'b' * 64}, {'исход': 'успех', 'длительностьНс': 1}, {'длительностьНс': 0}):
            with сам.subTest(изменения=изменения):
                with модуль.область_гостя(сам.корень, сам.владелец) as каталог:
                    путь = сам.создать(каталог, 'начало', **изменения)
                    try:
                        with сам.assertRaises(ValueError): сам.собрать(каталог)
                    finally: путь.unlink()

    def test_подменённое_имя_ссылка_и_канал_отклоняются(сам):
        with модуль.область_гостя(сам.корень, сам.владелец) as каталог:
            путь = сам.создать(каталог, 'начало')
            иной = сам.корень / ('начало-42345678-1234-4234-8234-123456789abc.json')
            путь.rename(иной)
            with сам.assertRaises(ValueError): сам.собрать(каталог)
            иной.unlink(); иной.symlink_to('/неизвестная-фикстура')
            with сам.assertRaises(ValueError): сам.собрать(каталог)
            иной.unlink(); os.mkfifo(иной, 0o600)
            with сам.assertRaises(ValueError): сам.собрать(каталог)

    def test_чтение_не_создаёт_отсутствующее_состояние(сам):
        with сам.assertRaises(ValueError):
            with модуль.область_гостя(сам.корень, сам.владелец, создать=False): pass
        сам.assertFalse(сам.корень.exists())
        with модуль.область_гостя(сам.корень, сам.владелец): pass
        (сам.корень / 'замок').unlink()
        with сам.assertRaises(ValueError):
            with модуль.область_гостя(сам.корень, сам.владелец, создать=False): pass
        сам.assertFalse((сам.корень / 'замок').exists())

    def test_полный_конверт_не_превышает_предел_хостового_хранилища(сам):
        данные = {'машина': сам.проверка, 'план': 'b' * 64, 'проверка': сам.проверка, 'исходник': 'a' * 64}
        with mock.patch.object(модуль.Path, 'read_text', return_value=сам.проверка), \
             mock.patch.object(модуль, 'область_гостя'), \
             mock.patch.object(модуль, 'собрать_измерения', return_value=[{'данные': 'ё' * (2 * 1024**2)}]):
            with сам.assertRaisesRegex(ValueError, 'предел'):
                модуль.экспортировать_измерения(данные)


if __name__ == '__main__': unittest.main()

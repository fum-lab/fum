import unittest
from unittest import mock

ресурсы = Path(__file__).resolve().parents[2] / 'Sources/ЯдроМашины/Ресурсы'
фикстура = Path(__file__).with_name('test_наблюдатель.py')
родитель = '12345678-1234-4234-8234-123456789abc'
проверка = '22345678-1234-4234-8234-123456789abc'
владелец = {'схема': 'открытая-фикстура.1'}


def загрузить():
    область = {'__name__': 'гость_без_пути'}
    exec(compile((ресурсы / 'готовность.py').read_bytes(), '<гость>', 'exec'), область)
    assert '__file__' not in область
    return область


def источники():
    return {имя: (ресурсы / (имя + '.py')).read_bytes().decode('utf-8')
            for имя in ('наблюдатель', 'родитель_наблюдателя')}


def запустить_фазу(корень, режим):
    область = загрузить(); данные = источники()
    with область['область_гостя'](корень, владелец, вернуть_замок=True) as (каталог, замок):
        исполнитель = область['загрузить_исполнителя'](данные)
        метрики = область['ИзмеренияГостя'](родитель, каталог, проверка, 'a' * 64,
            замок=замок, наблюдатель=данные['наблюдатель'], исполнитель=исполнитель)
        with метрики.этап('Готовность Linux'):
            return метрики.команда('Завершение cloud-init', [sys.executable, '-B', str(фикстура), '--команда', str(корень), режим],
                каталог=корень, среда={'PATH': '/usr/bin:/bin'}, вход='точные байты\n'.encode(), предел=4)


class ПроверкиИзмерений(unittest.TestCase):
    def setUp(сам):
        сам.временный = tempfile.TemporaryDirectory(); сам.addCleanup(сам.временный.cleanup)
        сам.основа = Path(сам.временный.name).resolve(); сам.корень = сам.основа / 'гость'
        сам.область = загрузить(); сам.данные = источники()

    def метрики(сам, каталог, замок, **изменения):
        параметры = dict(замок=замок, наблюдатель=сам.данные['наблюдатель'],
                         исполнитель=сам.область['загрузить_исполнителя'](сам.данные))
        параметры.update(изменения)
        return сам.область['ИзмеренияГостя'](родитель, каталог, проверка, 'a' * 64, **параметры)

    def открыть(сам):
        return сам.область['область_гостя'](сам.корень, владелец, вернуть_замок=True)

    def свободен(сам):
        номер = os.open(сам.корень / 'замок', os.O_RDWR)
        try:
            try: fcntl.flock(номер, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError: return False
            return True
        finally: os.close(номер)

    def дождаться(сам, условие, предел=5):
        конец = time.monotonic() + предел
        while time.monotonic() < конец:
            if условие(): return
            time.sleep(0.01)
        сам.fail('Не получено свидетельство дочернего процесса')

    def фазы(сам):
        return [json.loads(путь.read_bytes()) for префикс in ('начало-', 'конец-')
                for путь in сам.корень.glob(префикс + '*.json')]

    def test_точные_ресурсы_байты_среда_cwd_и_происхождение_квитанции(сам):
        сам.данные['родитель_наблюдателя'] += '\nassert "__file__" not in globals()\n'
        сам.данные['наблюдатель'] += '\n# Открытые точные байты ё\n'
        with сам.открыть() as (каталог, замок):
            метрики = сам.метрики(каталог, замок)
            код = 'import json,os,sys; print(json.dumps([os.getcwd(),os.environ.get("OPEN_VALUE"),sys.argv[1],sys.stdin.buffer.read().hex()],ensure_ascii=False))'
            вход = 'stdin ё\0\n'.encode()
            результат = метрики.команда('Открытая команда', [sys.executable, '-c', код, 'аргумент ё'],
                каталог=сам.корень, среда={'OPEN_VALUE': 'среда ё'}, вход=вход)
            сам.assertEqual(json.loads(результат), [str(сам.корень), 'среда ё', 'аргумент ё', вход.hex()])
            сам.assertFalse(сам.свободен()); os.fstat(каталог); os.fstat(замок)
            начало, конец = sorted(сам.фазы(), key=lambda фаза: фаза['исход'] != 'выполняется')
            сам.assertEqual((начало['родитель'], начало['запуск'], начало['происхождение']), (родитель, проверка, 'a' * 64))
            сам.assertEqual((начало['идентификатор'], конец['исход']), (конец['идентификатор'], 'успех'))
            квитанция = json.loads(next(сам.корень.glob('наблюдатель-*-конец.json')).read_bytes())
            сам.assertEqual((квитанция['родитель'], квитанция['проверка'], квитанция['исходник']), (начало['идентификатор'], проверка, 'a' * 64))
            сам.assertNotEqual(квитанция['идентификатор'], начало['идентификатор'])
            манифест = json.loads(next(сам.корень.glob('отправка-наблюдателя-*.json')).read_bytes())
            сам.assertEqual(манифест['аргументы'][5], сам.данные['наблюдатель'])
            сам.assertEqual(json.loads(манифест['описание'])['каталог'], str(сам.корень))
            сам.assertEqual((сам.корень / манифест['файлы']['вход']).read_bytes(), вход)
            экспорт = сам.область['собрать_измерения'](каталог, проверка, 'a' * 64)
            сам.assertEqual(len(экспорт), 2)

    def test_пустая_среда_и_вход_не_подменяются_значениями_по_умолчанию(сам):
        with сам.открыть() as (каталог, замок):
            метрики = сам.метрики(каталог, замок)
            результат = метрики.команда('Пустой вход', [sys.executable, '-c', 'import sys; sys.stdout.buffer.write(sys.stdin.buffer.read())'],
                каталог=сам.корень, среда={}, вход=b'')
            сам.assertEqual(результат, b'')
            манифест = json.loads(next(сам.корень.glob('отправка-наблюдателя-*.json')).read_bytes())
            сам.assertEqual(json.loads(манифест['описание'])['среда'], {})
            сам.assertEqual(манифест['вход_байт'], 0)

    def test_ошибки_команды_и_самого_наблюдателя_закрывают_этапы_ошибкой(сам):
        for наблюдатель, код in [(сам.данные['наблюдатель'], 17), ('raise SystemExit(125)\n', 0)]:
            with сам.subTest(код=код):
                with сам.открыть() as (каталог, замок):
                    метрики = сам.метрики(каталог, замок, наблюдатель=наблюдатель)
                    до = {фаза['идентификатор'] for фаза in сам.фазы()}
                    with сам.assertRaises(ValueError) as ошибка:
                        with метрики.этап('Внешний этап'):
                            метрики.команда('Отказ', [sys.executable, '-c', 'import sys; sys.stderr.write("ошибка ё"); sys.exit(' + str(код) + ')'], каталог=сам.корень)
                    новые = [фаза for фаза in сам.фазы() if фаза['идентификатор'] not in до]
                    сам.assertEqual(len(новые), 4)
                    сам.assertTrue(all(фаза['исход'] == 'ошибка' for фаза in новые if фаза['длительностьНс'] is not None))
                    if код:
                        квитанция = json.loads(next(сам.корень.glob('наблюдатель-*-конец.json')).read_bytes())
                        сам.assertIn(квитанция['идентификатор'], str(ошибка.exception)); сам.assertIn('17', str(ошибка.exception))
                        сам.assertIn('завершение', str(ошибка.exception))
                    сам.assertFalse(сам.свободен())

    def test_срок_и_предел_вывода_сохраняют_ошибочную_фазу(сам):
        with сам.открыть() as (каталог, замок):
            метрики = сам.метрики(каталог, замок)
            for режим, причина in [('семейство', 'срок'), ('поток', 'вывод')]:
                with сам.subTest(режим=режим):
                    with сам.assertRaisesRegex(ValueError, причина):
                        метрики.команда('Предел', [sys.executable, '-B', str(фикстура), '--команда', str(сам.корень), режим],
                            каталог=сам.корень, предел=0.6 if режим == 'семейство' else 4)
                    сам.assertEqual(метрики.события[-1]['исход'], 'ошибка')
                    сам.assertFalse(сам.свободен())

    def test_источники_обязательны_ограничены_а_Git_без_метрик_запрещён(сам):
        for изменение in ({'наблюдатель': ''}, {'наблюдатель': 'ё' * (128 * 1024 + 1)},
                          {'родитель_наблюдателя': 'ё' * (128 * 1024 + 1)}, {'родитель_наблюдателя': '# нет функции\n'}):
            with сам.subTest(изменение=list(изменение)):
                with сам.assertRaises(ValueError): сам.область['загрузить_исполнителя']({**сам.данные, **изменение})
        with сам.assertRaises(ValueError): сам.область['загрузить_исполнителя']({})
        with сам.assertRaisesRegex(ValueError, 'метрик'):
            сам.область['команда_репозитория'](сам.основа, ['--version'], {})

    def test_истёкший_до_команды_срок_сохраняет_причину_UUID_и_отсутствующий_код(сам):
        with сам.открыть() as (каталог, замок):
            метрики = сам.метрики(каталог, замок)
            with сам.assertRaisesRegex(ValueError, 'причина срок') as ошибка:
                метрики.команда('Ранний срок', [sys.executable, '-c', 'print("не запускать")'],
                    каталог=сам.корень, предел=0.000000001)
            квитанция = json.loads(next(сам.корень.glob('наблюдатель-*-конец.json')).read_bytes())
            сам.assertIsNone(квитанция['код_команды'])
            сам.assertIn(квитанция['идентификатор'], str(ошибка.exception))
            сам.assertIn('код None', str(ошибка.exception))
            сам.assertEqual(метрики.события[-1]['исход'], 'ошибка')

    def test_готовность_передаёт_удерживаемые_FD_и_ресурсы_первой_команде(сам):
        сам.корень = сам.основа / '.fum-linux-vm'
        данные = {**сам.данные, 'машина': родитель, 'запуск': родитель, 'родитель': родитель,
            'проверка': проверка, 'план': 'b' * 64, 'исходник': 'a' * 64,
            'коммит': '4dd5a7f33913b17f705e512be1826314da89a4c4'}
        данные['родитель_наблюдателя'] += '''
исходный_исполнитель = исполнить_под_наблюдением
def исполнить_под_наблюдением(**параметры):
    assert параметры['аргументы'] == ['/usr/bin/cloud-init', 'status', '--wait', '--format', 'json']
    параметры['аргументы'] = [sys.executable, '-c', 'print("{}")']
    return исходный_исполнитель(**параметры)
'''
        исходное_чтение = Path.read_text
        def прочитать(путь, *части, **ключи):
            if str(путь) in ('/etc/fum-vm-id', '/proc/sys/kernel/random/boot_id'): return родитель
            return исходное_чтение(путь, *части, **ключи)
        with mock.patch.object(Path, 'home', return_value=сам.основа), \
             mock.patch.object(Path, 'read_text', прочитать), \
             mock.patch.object(platform, 'system', return_value='Linux'), \
             mock.patch.object(platform, 'machine', return_value='aarch64'), \
             mock.patch.object(platform, 'freedesktop_os_release', return_value={'ID': 'ubuntu', 'VERSION_ID': '24.04'}):
            with сам.assertRaisesRegex(ValueError, 'cloud-init'):
                сам.область['подтвердить_готовность'](данные)
        сам.assertIsNone(сам.область['ТЕКУЩИЕ_МЕТРИКИ']); сам.assertTrue(сам.свободен())
        начала = [фаза for фаза in сам.фазы() if фаза['исход'] == 'выполняется']
        концы = [фаза for фаза in сам.фазы() if фаза['исход'] != 'выполняется']
        сам.assertEqual({фаза['операция'] for фаза in начала}, {'Готовность Linux', 'Завершение cloud-init'})
        сам.assertEqual({фаза['операция']: фаза['исход'] for фаза in концы},
                        {'Готовность Linux': 'ошибка', 'Завершение cloud-init': 'успех'})
        сам.assertFalse(list(сам.корень.glob('готовность-*.json')))
        квитанция = json.loads(next(сам.корень.glob('наблюдатель-*-конец.json')).read_bytes())
        командная = next(фаза for фаза in начала if фаза['операция'] == 'Завершение cloud-init')
        сам.assertEqual(квитанция['родитель'], командная['идентификатор'])
        сам.assertEqual(квитанция['проверка'], проверка)

    def test_неверный_успешный_результат_не_создаёт_успешную_фазу(сам):
        with сам.открыть() as (каталог, замок):
            for правка in ({'код_команды': False}, {'исход': 'ошибка'}, {'причина': 'срок'}):
                with сам.subTest(правка=правка):
                    результат = dict(идентификатор=родитель, причина='завершение', исход='успех', код_команды=0, вывод=b'', ошибки=b'')
                    результат.update(правка)
                    метрики = сам.метрики(каталог, замок, исполнитель=lambda **_: результат)
                    with сам.assertRaises(ValueError): метрики.команда('Непринятая команда', ['/открытая-фикстура'], каталог=сам.корень)
                    сам.assertEqual(метрики.события[-1]['исход'], 'ошибка')

    def test_SIGKILL_родителя_оставляет_неполный_экспорт_без_повтора_команды(сам):
        контроль = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(8)'])
        # Через единственный stdin исполняется ресурс, которому не дан __file__.
        программа = ('from pathlib import Path\n' + (ресурсы / 'готовность.py').read_text()
            + '\nданные = json.loads(bytes.fromhex(' + json.dumps(json.dumps(сам.данные).encode().hex()) + '))\n'
            + 'корень = Path(' + repr(str(сам.корень)) + ')\n'
            + 'with область_гостя(корень, ' + repr(владелец) + ', вернуть_замок=True) as (каталог, замок):\n'
            + '    метрики = ИзмеренияГостя(' + repr(родитель) + ', каталог, ' + repr(проверка) + ', "' + 'a' * 64 + '", замок=замок, наблюдатель=данные["наблюдатель"], исполнитель=загрузить_исполнителя(данные))\n'
            + '    with метрики.этап("Готовность Linux"):\n'
            + '        метрики.команда("Завершение cloud-init", ' + repr([sys.executable, '-B', str(фикстура), '--команда', str(сам.корень), 'семейство']) + ', каталог=корень, предел=4)\n')
        процесс = subprocess.Popen([sys.executable, '-B', '-c', 'import sys; exec(compile(sys.stdin.buffer.read(),"<единый stdin>","exec"),{"__name__":"гость"})'],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        try:
            процесс.stdin.write(программа.encode()); процесс.stdin.close()
            сам.дождаться(lambda: (сам.корень / 'пульс').exists())
            снимок = {путь.name: путь.read_bytes() for путь in сам.корень.glob('начало-*.json')}
            сам.assertEqual(len(снимок), 2); сам.assertFalse(сам.свободен())
            процесс.kill(); процесс.wait(timeout=3)
            if сам.свободен():
                квитанция = json.loads(next(сам.корень.glob('наблюдатель-*-конец.json')).read_bytes())
                сам.assertTrue(квитанция['группа_исчезла'])
            сам.дождаться(сам.свободен)
            with сам.область['область_гостя'](сам.корень, владелец, создать=False) as каталог:
                до = {путь.name: путь.read_bytes() for путь in сам.корень.iterdir()}
                экспорт = сам.область['собрать_измерения'](каталог, проверка, 'a' * 64)
                сам.assertEqual(экспорт, сам.область['собрать_измерения'](каталог, проверка, 'a' * 64))
                сам.assertEqual(len(экспорт), 2)
                сам.assertEqual(снимок, {запись['имя']: запись['данные'].encode() for запись in экспорт})
                сам.assertFalse(list(сам.корень.glob('конец-*.json')))
                сам.assertEqual(до, {путь.name: путь.read_bytes() for путь in сам.корень.iterdir()})
                квитанция = json.loads(next(сам.корень.glob('наблюдатель-*-конец.json')).read_bytes())
                сам.assertEqual(квитанция['причина'], 'родитель_исчез')
                сам.assertTrue(квитанция['группа_исчезла'])
                командная = next(json.loads(байты) for байты in снимок.values()
                                 if json.loads(байты)['операция'] == 'Завершение cloud-init')
                сам.assertEqual(квитанция['родитель'], командная['идентификатор'])
                размер = (сам.корень / 'пульс').stat().st_size
                time.sleep(0.1); сам.assertEqual((сам.корень / 'пульс').stat().st_size, размер)
            сам.assertIsNone(контроль.poll())
        finally:
            if процесс.poll() is None: процесс.kill(); процесс.wait(timeout=3)
            процесс.stdout.close(); процесс.stderr.close()
            if контроль.poll() is None: контроль.kill(); контроль.wait(timeout=3)


if __name__ == '__main__': unittest.main()

import XCTest
@testable import ЯдроМашины

final class ПроверкиКонвейера: XCTestCase {
    func testГотовыйРезультатПовторноНеВыполняется() throws {
        var вызовы = 0
        try Конвейер.шаг(проверить: { true }, выполнить: { вызовы += 1 })
        XCTAssertEqual(вызовы, 0)
    }
    func testУспешныйВыходБезРезультатаНеЯвляетсяГотовностью() {
        XCTAssertThrowsError(try Конвейер.шаг(проверить: { false }, выполнить: {}))
    }
    func testПрерываниеИПродолжениеБезПовторнойГотовойРаботы() throws {
        var готов = false, прервать = true, вызовы = 0
        func выполнить() throws {
            вызовы += 1
            if прервать { throw ОшибкаМашины("прерывание фикстуры") }
            готов = true
        }
        XCTAssertThrowsError(try Конвейер.шаг(проверить: { готов }, выполнить: выполнить))
        прервать = false
        try Конвейер.шаг(проверить: { готов }, выполнить: выполнить)
        try Конвейер.шаг(проверить: { готов }, выполнить: выполнить)
        XCTAssertEqual(вызовы, 2)
    }
}

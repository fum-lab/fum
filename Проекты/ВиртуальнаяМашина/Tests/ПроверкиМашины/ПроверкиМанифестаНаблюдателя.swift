    func новыйМанифест(_ образец: МанифестГотовностиГостя, проверка: String? = nil,
                       наблюдатель: String = "# Открытый наблюдатель\n",
                       родительНаблюдателя: String = "# Открытый адаптер\n",
                       исходник: String = "import json, os\n", счётчик: String = "# Открытый счётчик\n") throws -> МанифестГотовностиГостя {
        let тело = try JSONDecoder().decode([String: String].self, from: образец.данные)
        var запуск = ЗапускМашины(машина: образец.контекст.машина, план: образец.контекст.план,
            портДоступаКГостю: 45678, портУправления: 45679)
        запуск.запуск = тело["запуск"]!
        return try МанифестГотовностиГостя.создать(запуск: запуск, родитель: образец.контекст.родитель,
            проверка: проверка ?? образец.контекст.проверка, коммит: тело["коммит"]!, ожидаемыеДанные: "",
            исходник: исходник, счётчик: счётчик, наблюдатель: наблюдатель, родительНаблюдателя: родительНаблюдателя)
    }
    func прежнийМанифест(_ образец: МанифестГотовностиГостя) throws -> МанифестГотовностиГостя {
        // Прежний wire-контракт создаётся отдельно и не дополняется текущими ресурсами.

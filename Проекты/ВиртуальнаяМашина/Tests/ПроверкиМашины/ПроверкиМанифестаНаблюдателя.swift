            портДоступаКГостю: 45678, портУправления: 45679)
        запуск.запуск = "52345678-1234-4234-8234-123456789abc"
        return try МанифестГотовностиГостя.создать(запуск: запуск, родитель: образец.контекст.родитель,
            проверка: "62345678-1234-4234-8234-123456789abc", коммит: тело["коммит"]!, ожидаемыеДанные: "",
            исходник: "# Прежняя программа v1\nimport json, os\n", счётчик: "# Прежний счётчик\n")
    }
    func test_НовыйМанифестЗакрепляетЧетыреРесурсаИГраницы() throws {
        try вХранилище { _, манифест in
            XCTAssertEqual(манифест.схема, "fum.манифест-готовности.2")
            let тело = try JSONDecoder().decode([String: String].self, from: манифест.данные)
            XCTAssertEqual(тело.count, 11)
            XCTAssertEqual(манифест.контекст.исходник, хэш(try кодировать([
                "готовность.py": манифест.исходник, "проверить-набор.py": манифест.счётчик,
                "наблюдатель.py": Data(тело["наблюдатель"]!.utf8),
                "родитель_наблюдателя.py": Data(тело["родитель_наблюдателя"]!.utf8)])))
            let первый = try новыйМанифест(манифест, наблюдатель: "# a\n", родительНаблюдателя: "# b\n# c\n")
            let второй = try новыйМанифест(манифест, наблюдатель: "# a\n# b\n", родительНаблюдателя: "# c\n")
            XCTAssertNotEqual(первый.контекст.исходник, второй.контекст.исходник)
            for (наблюдатель, родитель) in [("# иной\n", тело["родитель_наблюдателя"]!), (тело["наблюдатель"]!, "# иной\n")] {
                XCTAssertNotEqual(манифест.контекст.исходник,
                    try новыйМанифест(манифест, наблюдатель: наблюдатель, родительНаблюдателя: родитель).контекст.исходник)
            }
            let исходник = try РесурсыГостя.текст("готовность.py"), счётчик = try РесурсыГостя.текст("проверить-набор.py")
            let наблюдатель = try РесурсыГостя.текст("наблюдатель.py"), родитель = try РесурсыГостя.текст("родитель_наблюдателя.py")
            var интервалы: [UInt64] = [], вход = Data(), отпечаток = ""
            for _ in 0..<3 {
                let начало = DispatchTime.now().uptimeNanoseconds
                let полный = try новыйМанифест(манифест, наблюдатель: наблюдатель, родительНаблюдателя: родитель,
                    исходник: исходник, счётчик: счётчик)
                try полный.проверить(); _ = try полный.входЭкспорта()
                интервалы.append(DispatchTime.now().uptimeNanoseconds - начало)
                if !вход.isEmpty { XCTAssertEqual(вход, полный.вход) }
                вход = полный.вход; отпечаток = полный.контекст.исходник
            }
            let профиль: [String: Any] = ["схема": "fum.профиль-манифеста-наблюдателя.1", "исходник_sha256": отпечаток,
                "вход_sha256": хэш(вход), "интервалы_нс": интервалы, "медиана_нс": интервалы.sorted()[1], "предкритерий_нс": 250_000_000]
            print("ПРОФИЛЬ_МАНИФЕСТА_НАБЛЮДАТЕЛЯ " + String(decoding: try JSONSerialization.data(withJSONObject: профиль, options: [.sortedKeys]), as: UTF8.self))
        }
    }
    func test_ВерсияРазмерИПодменаРесурсаЗакрываютОтправку() throws {
        try вХранилище { хранилище, манифест in
            for строка in ["", String(repeating: "ё", count: 131_073)] {
                XCTAssertThrowsError(try новыйМанифест(манифест, наблюдатель: строка))
                XCTAssertThrowsError(try новыйМанифест(манифест, родительНаблюдателя: строка))
            }
            XCTAssertThrowsError(try новыйМанифест(манифест, наблюдатель: String(repeating: "a", count: 256 * 1024),
                родительНаблюдателя: String(repeating: "b", count: 256 * 1024),
                исходник: String(repeating: "c", count: 512 * 1024), счётчик: String(repeating: "d", count: 512 * 1024)))
            for вариант in 0..<4 {
                var тело = try JSONDecoder().decode([String: String].self, from: манифест.данные)
                var схема = манифест.схема
                switch вариант {
                case 0: тело.removeValue(forKey: "наблюдатель")
                case 1: тело["родитель_наблюдателя"] = "# подмена\n"
                case 2: схема = "fum.манифест-готовности.3"
                default: схема = "fum.манифест-готовности.1"
                }
                let данные = try кодировать(тело)
                let изменённый = МанифестГотовностиГостя(схема: схема, контекст: манифест.контекст,
                    исходник: манифест.исходник, счётчик: манифест.счётчик, данные: данные,
                    вход: ДоступКГостю.сценарий(исходник: String(decoding: манифест.исходник, as: UTF8.self), вызов: "подтвердить_готовность", данные: данные))
                XCTAssertThrowsError(try ОбменГотовностьюГостя.выполнить(изменённый, хранилище: хранилище) { _, _ in
                    XCTFail("Недействительный манифест отправлен"); throw ОшибкаМашины("лишний транспорт")
                })
                XCTAssertFalse(try хранилище.есть(манифест.имя))
            }
        }
    }
    func test_ПрежнийМанифестВосстанавливаетсяБезПерезаписиИНовогоИсполнения() throws {
        try вХранилище { хранилище, образец in
            let прежний = try прежнийМанифест(образец), байты = try кодировать(прежний)
            try хранилище.записать(прежний.имя, байты: байты)
            let файл = try хранилище.открытьФайл(прежний.имя); defer { close(файл) }
            var до = stat(); XCTAssertEqual(fstat(файл, &до), 0)
            var вызовы = 0
            _ = try ОбменГотовностьюГостя.восстановить(хранилище) { вход, черезХост in
                вызовы += 1; XCTAssertFalse(черезХост); XCTAssertEqual(вход, try прежний.входЭкспорта())
                XCTAssertTrue(вход.starts(with: прежний.исходник))
                return try результат(пакет([фикстура(прежний).1[0]], прежний))
            }
            XCTAssertEqual(вызовы, 1)
            let второй = try хранилище.открытьФайл(прежний.имя); defer { close(второй) }
            var после = stat(); XCTAssertEqual(fstat(второй, &после), 0)
            XCTAssertEqual(до.st_ino, после.st_ino); XCTAssertEqual(байты, try хранилище.прочитать(прежний.имя))
            XCTAssertFalse(try хранилище.есть("готовность.json"))
            XCTAssertThrowsError(try ОбменГотовностьюГостя.выполнить(прежний, хранилище: хранилище) { _, _ in
                XCTFail("v1 запущен как новая готовность"); throw ОшибкаМашины("лишний транспорт")
            })
        }
    }
    func test_АрхивДвухВерсийРазделяетПроверкиИНеПовторяетЗавершённую() throws {
        try вХранилище { хранилище, новый in
            let прежний = try прежнийМанифест(новый)
            try прежний.сохранить(хранилище); try новый.сохранить(хранилище)
            let (_, старыеФазы) = try фикстура(прежний), (_, новыеФазы) = try фикстура(новый)
            _ = try СохранениеГостевыхИзмерений.принять(пакет(старыеФазы, прежний), манифест: прежний, хранилище: хранилище)
            var вызовы = 0
            let итоги = try ОбменГотовностьюГостя.восстановить(хранилище) { вход, черезХост in
                вызовы += 1; XCTAssertFalse(черезХост); XCTAssertEqual(вход, try новый.входЭкспорта())
                return try результат(пакет(новыеФазы, новый))
            }
            XCTAssertEqual(вызовы, 1); XCTAssertEqual(итоги.count, 2)
            XCTAssertEqual(Set(итоги.map(\.проверка)), [прежний.контекст.проверка, новый.контекст.проверка])
            XCTAssertTrue(итоги.allSatisfy { $0.состояние == "завершено" })
            let имя = "измерения-гостя-" + новый.контекст.проверка + ".json", сохранённые = try хранилище.прочитать(имя)
            XCTAssertThrowsError(try СохранениеГостевыхИзмерений.принять(пакет(старыеФазы, прежний), манифест: новый, хранилище: хранилище))
            XCTAssertEqual(сохранённые, try хранилище.прочитать(имя))
        }
    }

import XCTest
@testable import ЯдроМашины

final class ПроверкиИмпортаИзмерений: XCTestCase {
    let контекст = КонтекстГостевыхИзмерений(машина: "12345678-1234-4234-8234-123456789abc",
        план: String(repeating: "a", count: 64), проверка: "22345678-1234-4234-8234-123456789abc",
        исходник: String(repeating: "b", count: 64), родитель: "32345678-1234-4234-8234-123456789abc")
    let событие = "42345678-1234-4234-8234-123456789abc"
    func файл(_ фаза: String, изменить: (inout [String: Any]) -> Void = { _ in }) throws -> [String: Any] {
        var тело: [String: Any] = ["идентификатор": событие, "родитель": контекст.родитель,
            "операция": "Готовность Linux", "исход": фаза == "начало" ? "выполняется" : "успех",
            "длительностьНс": фаза == "начало" ? NSNull() : 10,
            "происхождение": контекст.исходник, "запуск": контекст.проверка]
        изменить(&тело)
        var данные = try JSONSerialization.data(withJSONObject: тело, options: [.sortedKeys])
        данные.append(10)
        return ["имя": фаза + "-" + событие + ".json", "sha256": хэш(данные), "данные": String(decoding: данные, as: UTF8.self)]
    }
    func пакет(_ файлы: [[String: Any]], изменить: (inout [String: Any]) -> Void = { _ in }) throws -> Data {
        var тело: [String: Any] = ["схема": "fum.измерения-гостя.1", "машина": контекст.машина,
            "план": контекст.план, "проверка": контекст.проверка, "исходник": контекст.исходник, "файлы": файлы]
        изменить(&тело)
        return try JSONSerialization.data(withJSONObject: тело, options: [.sortedKeys])
    }
    func test_КонецПередНачаломИПовторНеУдваиваютСобытие() throws {
        let начало = try пакет([файл("начало")])
        let всё = try пакет([файл("конец"), файл("начало")])
        let результат = try ИмпортГостевыхИзмерений.свести([начало, всё, всё], контекст: контекст)
        XCTAssertEqual(результат.файлы.count, 2)
        XCTAssertEqual(результат.события.count, 1)
        XCTAssertEqual(результат.завершённых, 1)
        XCTAssertEqual(результат.события[0].длительностьНс, 10)
        XCTAssertEqual(результат.файлы[0].данные, try файл("конец")["данные"] as? String)
        let обратный = try ИмпортГостевыхИзмерений.свести([пакет([файл("конец")]), начало], контекст: контекст)
        XCTAssertEqual(обратный.файлы, результат.файлы)
        XCTAssertEqual(обратный.события, результат.события)
    }
    func test_ОдиночныеФазыИОшибкаНеДаютПолнойГотовности() throws {
        for фаза in ["начало", "конец"] {
            let сводка = try ИмпортГостевыхИзмерений.свести([пакет([файл(фаза)])], контекст: контекст)
            XCTAssertEqual(сводка.завершённых, 0)
            XCTAssertNil(сводка.события[0].длительностьНс)
            XCTAssertThrowsError(try сводка.подтвердитьПрофиль())
        }
        let ошибка = try пакет([файл("начало"), файл("конец", изменить: { $0["исход"] = "ошибка" })])
        let сводка = try ИмпортГостевыхИзмерений.свести([ошибка], контекст: контекст)
        XCTAssertEqual(сводка.завершённых, 1)
        XCTAssertThrowsError(try сводка.подтвердитьПрофиль())
    }
    func test_ЧужоеПроисхождениеИПодменаБайтовОтклоняются() throws {
        for ключ in ["машина", "план", "проверка", "исходник"] {
            let данные = try пакет([файл("начало")], изменить: {
                $0[ключ] = ["план", "исходник"].contains(ключ) ? String(repeating: "c", count: 64) : событие
            })
            XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([данные], контекст: контекст))
        }
        for ключ in ["родитель", "происхождение", "запуск"] {
            let данные = try пакет([файл("начало", изменить: {
                $0[ключ] = ключ == "происхождение" ? String(repeating: "c", count: 64) : контекст.машина
            })])
            XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([данные], контекст: контекст))
        }
        var подмена = try файл("начало"); подмена["sha256"] = String(repeating: "0", count: 64)
        XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([пакет([подмена])], контекст: контекст))
    }
    func test_КонфликтФазыИИзменениеМетаданныхНеЗаменяютПрежнее() throws {
        let прежний = try пакет([файл("начало"), файл("конец")])
        let изменённый = try пакет([файл("конец", изменить: { $0["длительностьНс"] = 11 })])
        XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([прежний, изменённый], контекст: контекст))
        let иной = try пакет([файл("начало"), файл("конец", изменить: { $0["операция"] = "Другая операция" })])
        XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([иной], контекст: контекст))
        for значение in [-1, true, "10", 1.5] as [Any] {
            XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([пакет([файл("конец", изменить: { $0["длительностьНс"] = значение })])], контекст: контекст))
        }
    }

    func дерево(_ первичный: Bool) -> [(String, String, String)] {
        var узлы: [(String, String, String)] = [(событие, контекст.родитель, "Готовность Linux")]
        func добавить(_ имя: String, _ родитель: String) -> String {
            let номер = String(format: "52345678-1234-4234-8234-%012d", узлы.count)
            узлы.append((номер, родитель, имя)); return номер
        }
        for имя in ["Завершение cloud-init", "Файловая система гостя", "Гостевой DNS",
                    "HTTPS через ограниченный хостовый туннель", "Версия Git"] { _ = добавить(имя, событие) }
        let клон = добавить("Подготовка точного гостевого клона", событие)
        let профиль = добавить("Переносимый профиль FUM", событие)
        let команды = ["for-each-ref", "config", "remote", "remote", "rev-parse", "rev-parse", "rev-parse",
                       "rev-parse", "rev-parse", "ls-tree", "ls-files", "ls-files"]
        for родитель in [клон, профиль] { for имя in команды { _ = добавить("Git: " + имя, родитель) } }
        if первичный { for имя in ["init", "remote", "fetch", "cat-file", "checkout"] { _ = добавить("Git: " + имя, клон) } }
        for имя in ["fum-proyektnyiye-fajlyi", "fum-moskovskoye-vremya-rabochej-sessii", "fum-indeks-readme", "fum-obratnyiye-ssyilki-voprosov"] {
            _ = добавить("Набор " + имя, профиль)
        }
        for имя in ["fum-indeks-readme", "fum-obratnyiye-ssyilki-voprosov"] { _ = добавить("Индекс " + имя, профиль) }
        return узлы
    }
    func фазыДерева(_ узлы: [(String, String, String)]) throws -> [[String: Any]] {
        try узлы.flatMap { номер, родитель, операция in
            try ["начало", "конец"].map { фаза in
                var запись = try файл(фаза, изменить: {
                    $0["идентификатор"] = номер; $0["родитель"] = родитель; $0["операция"] = операция
                })
                запись["имя"] = фаза + "-" + номер + ".json"
                return запись
            }
        }
    }
    func test_ТочныеДеревьяПервичногоИПовторногоПрофиляПринимаются() throws {
        for первичный in [false, true] {
            let файлы = try фазыДерева(дерево(первичный))
            let результат = try ИмпортГостевыхИзмерений.свести([пакет(файлы.reversed())], контекст: контекст)
            XCTAssertEqual(результат.завершённых, первичный ? 43 : 38)
            XCTAssertNoThrow(try результат.подтвердитьПрофиль())
        }
    }
    func test_ПодменаСоставаПриПрежнемЧислеИЦиклОтклоняются() throws {
        let исходные = дерево(false)
        for вариант in 0..<5 {
            var узлы = исходные
            switch вариант {
            case 0: узлы[8].1 = узлы[7].0 // Перенос Git из клона в профиль при том же total.
            case 1: узлы[8].2 = "Git: fetch"
            case 2: узлы[8].2 = узлы[9].2 // Та же команда дважды с разными UUID.
            case 3: узлы[8].1 = узлы[9].0; узлы[9].1 = узлы[8].0
            default: узлы[8].1 = узлы[8].0
            }
            XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([пакет(фазыДерева(узлы))], контекст: контекст).подтвердитьПрофиль())
        }
    }
    func test_ПотеряФазыЛишнийУзелИОшибкаРебёнкаЗакрываютГотовность() throws {
        let исходные = try фазыДерева(дерево(false))
        XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([пакет(Array(исходные.dropLast()))], контекст: контекст).подтвердитьПрофиль())
        var лишние = дерево(false)
        лишние.append(("62345678-1234-4234-8234-123456789abc", событие, "Версия Git"))
        XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([пакет(фазыДерева(лишние))], контекст: контекст).подтвердитьПрофиль())
        var ошибочные = исходные
        var тело = try XCTUnwrap(JSONSerialization.jsonObject(with: Data((ошибочные[3]["данные"] as! String).utf8)) as? [String: Any])
        тело["исход"] = "ошибка"
        let байты = try JSONSerialization.data(withJSONObject: тело)
        ошибочные[3]["данные"] = String(decoding: байты, as: UTF8.self); ошибочные[3]["sha256"] = хэш(байты)
        XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([пакет(ошибочные)], контекст: контекст).подтвердитьПрофиль())
    }
    func test_ПрофильТрёхОдинаковыхИмпортов() throws {
        let вход = try пакет(фазыДерева(дерево(true)).reversed())
        var интервалы: [UInt64] = []
        for _ in 0..<3 {
            let начало = DispatchTime.now().uptimeNanoseconds
            let сводка = try ИмпортГостевыхИзмерений.свести([вход, вход, вход], контекст: контекст)
            try сводка.подтвердитьПрофиль()
            интервалы.append(DispatchTime.now().uptimeNanoseconds - начало)
            XCTAssertEqual(сводка.файлы.count, 86)
            XCTAssertEqual(сводка.завершённых, 43)
        }
        let результат: [String: Any] = ["схема": "fum.профиль-импорта-гостя.1", "вход_sha256": хэш(вход),
            "событий": 43, "фаз": 86, "повторов_пакета": 3, "интервалы_нс": интервалы,
            "медиана_нс": интервалы.sorted()[1], "предкритерий_нс": 100_000_000]
        print("ПРОФИЛЬ_ИМПОРТА " + String(decoding: try JSONSerialization.data(withJSONObject: результат, options: [.sortedKeys]), as: UTF8.self))
        // Порог является критерием решения об оптимизации; медленный хост сам по себе не нарушает корректность.
    }
    func test_РавныеСтрокиНеПодменяютТочныеБайтыФазы() throws {
        let файлы = try фазыДерева(дерево(false))
        var повтор = файлы[6]
        let прежнее = try XCTUnwrap(повтор["данные"] as? String)
        let изменённое = прежнее.decomposedStringWithCanonicalMapping
        XCTAssertEqual(прежнее, изменённое)
        XCTAssertNotEqual(Data(прежнее.utf8), Data(изменённое.utf8))
        повтор["данные"] = изменённое // Прежний SHA не соответствует этим байтам.
        XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([пакет(файлы), пакет([повтор])], контекст: контекст))
        var другаяПара = файлы
        let конец = try XCTUnwrap(другаяПара[7]["данные"] as? String).decomposedStringWithCanonicalMapping
        другаяПара[7]["данные"] = конец; другаяПара[7]["sha256"] = хэш(Data(конец.utf8))
        XCTAssertThrowsError(try ИмпортГостевыхИзмерений.свести([пакет(другаяПара)], контекст: контекст))
    }
}

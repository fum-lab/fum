import Foundation
import Darwin
import XCTest
@testable import ЯдроМашины

final class ПроверкиСохраненияИзмерений: XCTestCase {
    let проверка = "12345678-1234-4234-8234-123456789abc"
    let родитель = "22345678-1234-4234-8234-123456789abc"
    let событие = "32345678-1234-4234-8234-123456789abc"

    func вХранилище(_ действие: (Хранилище, МанифестГотовностиГостя) throws -> Void) throws {
        let физический = try XCTUnwrap(realpath(FileManager.default.temporaryDirectory.path, nil))
        defer { free(физический) }
        let каталог = URL(fileURLWithPath: String(cString: физический)).appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: false)
        defer { try? FileManager.default.removeItem(at: каталог) }
        let план = try ПланМашины.создать(профиль: Профиль(), каталог: каталог.appendingPathComponent("машина").path,
            ресурсы: Ресурсы(архитектура: "arm64", виртуализация: true, процессоры: 10, памятьБайт: 64 << 30, свободноБайт: 100 << 30))
        let хранилище = try Хранилище(план: план, создать: true)
        let запуск = ЗапускМашины(машина: хранилище.паспорт.идентификатор, план: план.отпечаток,
            портДоступаКГостю: 45678, портУправления: 45679)
        let манифест = try МанифестГотовностиГостя.создать(запуск: запуск, родитель: родитель, проверка: проверка,
            коммит: Профиль().коммит, ожидаемыеДанные: "", исходник: "import json, os\n", счётчик: "# Открытый счётчик\n")
        try действие(хранилище, манифест)
    }
    func файл(_ фаза: String, _ манифест: МанифестГотовностиГостя,
              номер: String? = nil, родитель: String? = nil, операция: String = "Готовность Linux", время: Int = 10) throws -> [String: Any] {
        let номер = номер ?? событие
        let тело: [String: Any] = ["идентификатор": номер, "родитель": родитель ?? self.родитель,
            "операция": операция, "исход": фаза == "начало" ? "выполняется" : "успех",
            "длительностьНс": фаза == "начало" ? NSNull() : время,
            "происхождение": манифест.контекст.исходник, "запуск": проверка]
        var байты = try JSONSerialization.data(withJSONObject: тело, options: [.sortedKeys]); байты.append(10)
        return ["имя": фаза + "-" + номер + ".json", "sha256": хэш(байты), "данные": String(decoding: байты, as: UTF8.self)]
    }
    func пакет(_ файлы: [[String: Any]], _ манифест: МанифестГотовностиГостя) throws -> Data {
        try JSONSerialization.data(withJSONObject: ["схема": "fum.измерения-гостя.1", "машина": манифест.контекст.машина,
            "план": манифест.контекст.план, "проверка": проверка, "исходник": манифест.контекст.исходник, "файлы": файлы], options: [.sortedKeys])
    }
    func test_ПозднийКонецДополняетНачалоПовторСохраняетБайты() throws {
        try вХранилище { хранилище, манифест in
            try манифест.сохранить(хранилище)
            let началоПакет = try пакет([файл("начало", манифест)], манифест)
            let началоЗаписи = DispatchTime.now().uptimeNanoseconds
            let первая = try СохранениеГостевыхИзмерений.принять(началоПакет,
                манифест: манифест, хранилище: хранилище)
            let перваяДлительность = DispatchTime.now().uptimeNanoseconds - началоЗаписи
            XCTAssertEqual(первая.завершённых, 0)
            let конец = try пакет([файл("конец", манифест)], манифест)
            let началоДополнения = DispatchTime.now().uptimeNanoseconds
            let полная = try СохранениеГостевыхИзмерений.принять(конец, манифест: манифест, хранилище: хранилище)
            let дополнениеДлительность = DispatchTime.now().uptimeNanoseconds - началоДополнения
            XCTAssertEqual(полная.завершённых, 1); XCTAssertEqual(полная.файлы.count, 2)
            let имя = "измерения-гостя-" + проверка + ".json"
            let байты = try хранилище.прочитать(имя)
            var интервалы: [UInt64] = []
            for _ in 0..<3 {
                let начало = DispatchTime.now().uptimeNanoseconds
                _ = try СохранениеГостевыхИзмерений.принять(конец, манифест: манифест, хранилище: хранилище)
                интервалы.append(DispatchTime.now().uptimeNanoseconds - начало)
                XCTAssertEqual(байты, try хранилище.прочитать(имя))
            }
            let профиль: [String: Any] = ["схема": "fum.профиль-сохранения-измерений.1", "вход_sha256": хэш(конец),
                "манифест_sha256": хэш(try кодировать(манифест)), "фаз": 2, "первая_запись_нс": перваяДлительность,
                "дополнение_нс": дополнениеДлительность, "повторы_нс": интервалы,
                "медиана_повторов_нс": интервалы.sorted()[1], "предкритерий_нс": 100_000_000]
            print("ПРОФИЛЬ_СОХРАНЕНИЯ " + String(decoding: try JSONSerialization.data(withJSONObject: профиль, options: [.sortedKeys]), as: UTF8.self))
            let изменённый = try пакет([файл("конец", манифест, время: 11)], манифест)
            XCTAssertThrowsError(try СохранениеГостевыхИзмерений.принять(изменённый, манифест: манифест, хранилище: хранилище))
            XCTAssertEqual(байты, try хранилище.прочитать(имя))
        }
    }
    func test_НесохранённыйМанифестИПовреждённаяИсторияНеПринимаются() throws {
        try вХранилище { хранилище, манифест in
            let вход = try пакет([файл("начало", манифест)], манифест)
            XCTAssertThrowsError(try СохранениеГостевыхИзмерений.принять(вход, манифест: манифест, хранилище: хранилище))
            try манифест.сохранить(хранилище)
            let имя = "измерения-гостя-" + проверка + ".json"
            try хранилище.записать(имя, байты: Data("Повреждённая история".utf8))
            XCTAssertThrowsError(try СохранениеГостевыхИзмерений.принять(вход, манифест: манифест, хранилище: хранилище))
            XCTAssertEqual(try хранилище.прочитать(имя), Data("Повреждённая история".utf8))
        }
    }
    func test_ПределИтоговогоДокументаПроверяетсяДоЗаменыИстории() throws {
        try вХранилище { хранилище, манифест in
            try манифест.сохранить(хранилище)
            var первая = [try файл("начало", манифест)]
            var вторая: [[String: Any]] = []
            for номер in 0..<2400 {
                let запись = try файл("начало", манифест, номер: String(format: "42345678-1234-4234-8234-%012d", номер),
                    родитель: событие, операция: String(repeating: "\"", count: 512))
                if номер < 1200 { первая.append(запись) } else { вторая.append(запись) }
            }
            let первыйПакет = try пакет(первая, манифест), второйПакет = try пакет(вторая, манифест)
            XCTAssertLessThan(первыйПакет.count, 4 * 1024 * 1024)
            XCTAssertLessThan(второйПакет.count, 4 * 1024 * 1024)
            let сводка = try ИмпортГостевыхИзмерений.свести([первыйПакет, второйПакет], контекст: манифест.контекст)
            XCTAssertLessThan(сводка.файлы.reduce(0) { $0 + $1.данные.utf8.count }, 4 * 1024 * 1024)
            _ = try СохранениеГостевыхИзмерений.принять(первыйПакет, манифест: манифест, хранилище: хранилище)
            let имя = "измерения-гостя-" + проверка + ".json", прежнее = try хранилище.прочитать(имя)
            XCTAssertThrowsError(try СохранениеГостевыхИзмерений.принять(второйПакет, манифест: манифест, хранилище: хранилище))
            XCTAssertEqual(прежнее, try хранилище.прочитать(имя))
        }
    }
}

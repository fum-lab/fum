final class ПроверкиОбменаГотовностью: XCTestCase {
    func вХранилище(_ действие: (Хранилище, МанифестГотовностиГостя) throws -> Void) throws {
        let физический = try XCTUnwrap(realpath(FileManager.default.temporaryDirectory.path, nil))
        defer { free(физический) }
        let каталог = URL(fileURLWithPath: String(cString: физический)).appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: каталог, withIntermediateDirectories: false)
        defer { try? FileManager.default.removeItem(at: каталог) }
        let план = try ПланМашины.создать(профиль: Профиль(), каталог: каталог.appendingPathComponent("машина").path,
            ресурсы: Ресурсы(архитектура: "arm64", виртуализация: true, процессоры: 10, памятьБайт: 64 << 30, свободноБайт: 100 << 30))
        let хранилище = try Хранилище(план: план, создать: true)
        let запуск = ЗапускМашины(машина: хранилище.паспорт.идентификатор, план: план.отпечаток,
            портДоступаКГостю: 45678, портУправления: 45679)
        let манифест = try МанифестГотовностиГостя.создать(запуск: запуск,
            родитель: "12345678-1234-4234-8234-123456789abc", проверка: "22345678-1234-4234-8234-123456789abc",
            коммит: Профиль().коммит, ожидаемыеДанные: "", исходник: "import json, os\n", счётчик: "# Открытый счётчик\n",
            наблюдатель: "# Открытый наблюдатель\n", родительНаблюдателя: "# Открытый адаптер\n")
        try действие(хранилище, манифест)
    }
    func пакет(_ файлы: [[String: Any]], _ манифест: МанифестГотовностиГостя) throws -> Data {
        try JSONSerialization.data(withJSONObject: ["схема": "fum.измерения-гостя.1", "машина": манифест.контекст.машина,
            "план": манифест.контекст.план, "проверка": манифест.контекст.проверка,
            "исходник": манифест.контекст.исходник, "файлы": файлы], options: [.sortedKeys])
    }
    func фикстура(_ манифест: МанифестГотовностиГостя) throws -> ([String: Any], [[String: Any]]) {
        // Открытое повторное дерево: семь верхних операций, 12 Git-шагов клона и 18 шагов профиля.
        var узлы: [(String, String, String)] = []
        func добавить(_ имя: String, _ родитель: String) -> String {
            let номер = String(format: "32345678-1234-4234-8234-%012d", узлы.count)
            узлы.append((номер, родитель, имя)); return номер
        }
        let корень = добавить("Готовность Linux", манифест.контекст.родитель)
        for имя in ["Завершение cloud-init", "Файловая система гостя", "Гостевой DNS",
                    "HTTPS через ограниченный хостовый туннель", "Версия Git"] { _ = добавить(имя, корень) }
        let клон = добавить("Подготовка точного гостевого клона", корень)
        let профиль = добавить("Переносимый профиль FUM", корень)
        for родитель in [клон, профиль] {
            for имя in ["for-each-ref", "config", "remote", "remote", "rev-parse", "rev-parse", "rev-parse",
                        "rev-parse", "rev-parse", "ls-tree", "ls-files", "ls-files"] { _ = добавить("Git: " + имя, родитель) }
        }
        let имена = ["fum-proyektnyiye-fajlyi", "fum-moskovskoye-vremya-rabochej-sessii", "fum-indeks-readme", "fum-obratnyiye-ssyilki-voprosov"]
        for имя in имена { _ = добавить("Набор " + имя, профиль) }
        for имя in имена.suffix(2) { _ = добавить("Индекс " + имя, профиль) }
        var файлы: [[String: Any]] = [], события: [[String: Any]] = []
        for (номер, родитель, операция) in узлы {
            for фаза in ["начало", "конец"] {
                let тело: [String: Any] = ["идентификатор": номер, "родитель": родитель, "операция": операция,
                    "длительностьНс": фаза == "начало" ? NSNull() : 10, "исход": фаза == "начало" ? "выполняется" : "успех",
                    "происхождение": манифест.контекст.исходник, "запуск": манифест.контекст.проверка]
                var байты = try JSONSerialization.data(withJSONObject: тело, options: [.sortedKeys]); байты.append(10)
                файлы.append(["имя": фаза + "-" + номер + ".json", "sha256": хэш(байты), "данные": String(decoding: байты, as: UTF8.self)])
                if фаза == "конец" { события.append(тело) }
            }
        }
        let запрос = try JSONDecoder().decode([String: String].self, from: манифест.данные)
        let ответ: [String: Any] = ["схема": "fum.готовность-гостя.1", "машина": манифест.контекст.машина,
            "план": манифест.контекст.план, "проверка": манифест.контекст.проверка, "запуск": запрос["запуск"]!,
            "гостевой_запуск": "42345678-1234-4234-8234-123456789abc", "коммит": Профиль().коммит,
            "дерево": "03e9f37be0717b35e9e87a46fe27e540cd071d63", "инициализация": "done",
            "файловая_система": "ext4", "сохранённые_данные": String(repeating: "b", count: 64), "события": события,
            "профиль": ["профиль": "fum.linux-portable.1", "тесты": 58, "проверки_индексов": 2,
                "наборы": zip(имена, [8, 4, 25, 21]).map { ["набор": $0, "счётчики": ["выполнено": $1, "ошибки": 0,
                    "отказы": 0, "пропущено": 0, "ожидаемые_ошибки": 0, "неожиданные_успехи": 0]] as [String: Any] }]]
        return (ответ, файлы)
    }
    func результат(_ данные: Data, код: Int32 = 0) -> РезультатПроцесса {
        РезультатПроцесса(код: код, вывод: String(decoding: данные, as: UTF8.self), ошибки: "")
    }
    func test_ДоОтправкиСохранёнТочныйЗапросПослеУспехаИмпортированыФазы() throws {
        try вХранилище { хранилище, манифест in
            let (тело, файлы) = try фикстура(манифест)
            let ответ = try JSONSerialization.data(withJSONObject: тело, options: [.sortedKeys])
            var вызовы: [Bool] = []
            let начало = DispatchTime.now().uptimeNanoseconds
            let итог = try ОбменГотовностьюГостя.выполнить(манифест, хранилище: хранилище) { вход, черезХост in
                вызовы.append(черезХост)
                XCTAssertEqual(try хранилище.прочитать(манифест.имя), try кодировать(манифест))
                XCTAssertEqual(вход, try черезХост ? манифест.вход : манифест.входЭкспорта())
                return try результат(черезХост ? ответ : пакет(файлы, манифест))
            }
            let длительность = DispatchTime.now().uptimeNanoseconds - начало
            XCTAssertEqual(итог, ответ); XCTAssertEqual(вызовы, [true, false])
            let профиль: [String: Any] = ["схема": "fum.профиль-обмена-готовностью.1",
                "манифест_sha256": хэш(try кодировать(манифест)), "ответ_sha256": хэш(ответ),
                "экспорт_sha256": хэш(try пакет(файлы, манифест)), "длительность_нс": длительность,
                "фаз": файлы.count, "транспорт": "открытая фикстура без SSH", "предкритерий_нс": 500_000_000]
            print("ПРОФИЛЬ_ОБМЕНА " + String(decoding: try JSONSerialization.data(withJSONObject: профиль, options: [.sortedKeys]), as: UTF8.self))
            let сохранённые = try хранилище.прочитать("измерения-гостя-" + манифест.контекст.проверка + ".json")
            XCTAssertNoThrow(try ИмпортГостевыхИзмерений.свести([сохранённые], контекст: манифест.контекст).подтвердитьПрофиль())
        }
    }
    func test_ПервичнаяОшибкаНеПодменяетсяНеуспешнымЭкспортом() throws {
        try вХранилище { хранилище, манифест in
            var вызовы: [Bool] = []
            XCTAssertThrowsError(try ОбменГотовностьюГостя.выполнить(манифест, хранилище: хранилище) { _, черезХост in
                вызовы.append(черезХост)
                return РезультатПроцесса(код: черезХост ? 17 : 23, вывод: "", ошибки: черезХост ? "первичный отказ" : "отказ экспорта")
            }) { ошибка in
                XCTAssertTrue(String(describing: ошибка).contains("17"))
                XCTAssertTrue(String(describing: ошибка).contains("первичный отказ"))
            }
            XCTAssertEqual(вызовы, [true, false])
            XCTAssertTrue(try хранилище.есть(манифест.имя))
            XCTAssertTrue(try хранилище.есть("повтор-импорта-" + манифест.контекст.проверка + ".json"))
        }
    }
    func test_ИсключениеТранспортаСохраняетНеполныеФазы() throws {
        try вХранилище { хранилище, манифест in
            let (_, файлы) = try фикстура(манифест)
            var вызовы: [Bool] = []
            XCTAssertThrowsError(try ОбменГотовностьюГостя.выполнить(манифест, хранилище: хранилище) { _, черезХост in
                вызовы.append(черезХост)
                if черезХост { throw ОшибкаМашины("прерванный транспорт") }
                return try результат(пакет([файлы[0]], манифест))
            }) { XCTAssertEqual(String(describing: $0), "прерванный транспорт") }
            XCTAssertEqual(вызовы, [true, false])
            let байты = try хранилище.прочитать("измерения-гостя-" + манифест.контекст.проверка + ".json")
            let сводка = try ИмпортГостевыхИзмерений.свести([байты], контекст: манифест.контекст)
            XCTAssertEqual(сводка.завершённых, 0); XCTAssertNil(сводка.события.first?.длительностьНс)
        }
    }
    func test_СчётчикиБезТехЖеКонечныхФазНеПодтверждаютГотовность() throws {
        for вариант in 0..<4 {
            try вХранилище { хранилище, манифест in
                var (ответ, файлы) = try фикстура(манифест)
                switch вариант {
                case 0: ответ["события"] = []
                case 1:
                    var события = ответ["события"] as! [[String: Any]]
                    события[1]["длительностьНс"] = 11; ответ["события"] = события
                case 2: файлы.removeLast()
                default:
                    var события = ответ["события"] as! [[String: Any]]
                    события[1]["происхождение"] = String(repeating: "c", count: 64); ответ["события"] = события
                }
                var вызовы: [Bool] = []
                XCTAssertThrowsError(try ОбменГотовностьюГостя.выполнить(манифест, хранилище: хранилище) { _, черезХост in
                    вызовы.append(черезХост)
                    return try результат(черезХост ? JSONSerialization.data(withJSONObject: ответ) : пакет(файлы, манифест))
                })
                XCTAssertEqual(вызовы, [true, false])
            }
        }
    }
    func test_ПовторЗабираетПрежнююПроверкуБезПовторногоИсполнения() throws {
        try вХранилище { хранилище, манифест in
            try манифест.сохранить(хранилище)
            let (_, файлы) = try фикстура(манифест)
            _ = try СохранениеГостевыхИзмерений.принять(пакет([файлы[0]], манифест), манифест: манифест, хранилище: хранилище)
            var вызовы = 0
            let итог = try ОбменГотовностьюГостя.восстановить(хранилище) { вход, черезХост in
                вызовы += 1; XCTAssertFalse(черезХост); XCTAssertEqual(вход, try манифест.входЭкспорта())
                return try результат(пакет(файлы, манифест))
            }
            XCTAssertEqual(вызовы, 1); XCTAssertEqual(итог.first?.проверка, манифест.контекст.проверка)
            XCTAssertEqual(итог.first?.состояние, "завершено")
            let имя = "измерения-гостя-" + манифест.контекст.проверка + ".json", прежнее = try хранилище.прочитать(имя)
            var интервалы: [UInt64] = []
            for _ in 0..<3 {
                let начало = DispatchTime.now().uptimeNanoseconds
                _ = try ОбменГотовностьюГостя.восстановить(хранилище) { _, _ in
                    XCTFail("Завершённые фазы не требуют повторной команды"); throw ОшибкаМашины("лишняя отправка")
                }
                интервалы.append(DispatchTime.now().uptimeNanoseconds - начало)
                XCTAssertEqual(прежнее, try хранилище.прочитать(имя))
            }
            let профиль: [String: Any] = ["схема": "fum.профиль-повтора-импорта.1", "история_sha256": хэш(прежнее),
                "манифест_sha256": хэш(try кодировать(манифест)), "интервалы_нс": интервалы,
                "медиана_нс": интервалы.sorted()[1], "предкритерий_нс": 100_000_000]
            print("ПРОФИЛЬ_ПОВТОРА " + String(decoding: try JSONSerialization.data(withJSONObject: профиль, options: [.sortedKeys]), as: UTF8.self))
        }
    }
    func test_ОтказВосстановленияСохраняетОжидающийЗапрос() throws {
        try вХранилище { хранилище, манифест in
            try манифест.сохранить(хранилище)
            let прежнее = try хранилище.прочитать(манифест.имя)
            let итоги = try ОбменГотовностьюГостя.восстановить(хранилище) { _, черезХост in
                XCTAssertFalse(черезХост); throw ОшибкаМашины("связь ещё не восстановлена")
            }
            XCTAssertEqual(итоги.first?.состояние, "ожидает экспорта")
            XCTAssertEqual(прежнее, try хранилище.прочитать(манифест.имя))
            XCTAssertTrue(try хранилище.есть("повтор-импорта-" + манифест.контекст.проверка + ".json"))
        }
    }
